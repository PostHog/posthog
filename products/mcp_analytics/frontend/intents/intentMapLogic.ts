import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { actionToUrl, urlToAction } from 'kea-router'
import posthog from 'posthog-js'

import type { ScatterAreaSelection } from '@posthog/quill-charts'

import api from 'lib/api'
import { FEATURE_FLAGS } from 'lib/constants'
import { type FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { dateFilterToText } from 'lib/utils/dateFilters'
import { urls } from 'scenes/urls'

import type {
    DateRange,
    MCPIntentMapPoint,
    MCPIntentMapQueryResponse,
    MCPIntentMapTopic,
} from '~/queries/schema/schema-general'
import { NodeKind } from '~/queries/schema/schema-general'

import {
    type IntentScatterSeries,
    type TopicColorSlots,
    assignTopicColorSlots,
    buildPointSeries,
    buildTopicSeries,
    topicColor,
} from './intentScatter'

export interface DateFilter {
    dateFrom: string | null
    dateTo: string | null
}

export const DEFAULT_DATE_FILTER: DateFilter = { dateFrom: '-7d', dateTo: null }
export const BASE_POINT_LIMIT = 2000
export const ZOOMED_POINT_LIMIT = 5000
export const TOPIC_POINTS_PAGE_SIZE = 50

const EMPTY_MAP: MCPIntentMapQueryResponse = { results: [], topics: [], total_points: 0 }

