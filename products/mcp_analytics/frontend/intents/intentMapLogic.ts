export type intentMapLogicType = MakeLogicType<
    intentMapLogicValues,
    intentMapLogicActions,
    Record<string, any>,
    intentMapLogicMeta
>

export const intentMapLogic = kea<intentMapLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'intents', 'intentMapLogic']),

    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),

    actions({
        setTool: (tool: string | null) => ({ tool }),
        setTopicId: (topicId: string | null) => ({ topicId }),
        // Applies every URL filter in one step and, unlike the setters, writes nothing back to the URL.
        hydrateFromUrl: (tool: string | null, topicId: string | null, dateFilter: DateFilter) => ({
            tool,
            topicId,
            dateFilter,
        }),
        setDateFilter: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setZoom: (zoom: ScatterAreaSelection | null) => ({ zoom }),
        selectTopic: (topicId: string | null) => ({ topicId }),
        focusTopic: (topicId: string) => ({ topicId }),
        showMoreTopicPoints: true,
    }),

    reducers({
        tool: [null as string | null, { setTool: (_, { tool }) => tool, hydrateFromUrl: (_, { tool }) => tool }],
        topicId: [
            null as string | null,
            { setTopicId: (_, { topicId }) => topicId, hydrateFromUrl: (_, { topicId }) => topicId },
        ],
        dateFilter: [
            DEFAULT_DATE_FILTER,
            {
                setDateFilter: (_, { dateFrom, dateTo }): DateFilter => ({ dateFrom, dateTo }),
                hydrateFromUrl: (_, { dateFilter }) => dateFilter,
            },
        ],
        // A drag selection pins the axes and loads the points inside it; null is the base view.
        zoom: [
            null as ScatterAreaSelection | null,
            {
                setZoom: (_, { zoom }) => zoom,
                setTool: () => null,
                setTopicId: () => null,
                setDateFilter: () => null,
                hydrateFromUrl: () => null,
            },
        ],
        // The topic whose panel is open. Independent of the topic filter so the panel can show a
        // bubble's details before the user narrows the map to it.
        selectedTopicId: [
            null as string | null,
            {
                selectTopic: (_, { topicId }) => topicId,
                setTopicId: (_, { topicId }) => topicId,
                hydrateFromUrl: (_, { topicId }) => topicId,
            },
        ],
        // A failed load keeps the last map, so the error lives apart from the data.
        mapError: [
            null as string | null,
            { loadMap: () => null, loadMapSuccess: () => null, loadMapFailure: (_, { error }) => error },
        ],
        // A zoomed topic can hold thousands of intents; the panel mounts them a page at a time.
        topicPointsShown: [
            TOPIC_POINTS_PAGE_SIZE as number,
            {
                showMoreTopicPoints: (shown) => shown + TOPIC_POINTS_PAGE_SIZE,
                selectTopic: () => TOPIC_POINTS_PAGE_SIZE,
                setTopicId: () => TOPIC_POINTS_PAGE_SIZE,
                hydrateFromUrl: () => TOPIC_POINTS_PAGE_SIZE,
                loadMapSuccess: () => TOPIC_POINTS_PAGE_SIZE,
            },
        ],
        // Narrowing to one topic or re-ranking reorders the topics, so colors follow first sight, not rank.
        topicColorSlots: [
            {} as TopicColorSlots,
            { loadMapSuccess: (slots, { map }) => assignTopicColorSlots(slots, map.topics ?? []) },
        ],
    }),

    loaders(({ values, cache }) => ({
        map: [
            EMPTY_MAP,
            {
                loadMap: async (_: void, breakpoint): Promise<MCPIntentMapQueryResponse> => {
                    if (!values.featureFlags[FEATURE_FLAGS.MCP_ANALYTICS_INTENT_TOPICS]) {
                        cache.skippedForFlag = true
                        return EMPTY_MAP
                    }
                    cache.skippedForFlag = false
                    await breakpoint(150)
                    const response = (await api.query({
                        kind: NodeKind.MCPIntentMapQuery,
                        dateRange: values.dateRange,
                        ...(values.tool ? { toolName: values.tool } : {}),
                        ...(values.topicId ? { topicId: values.topicId } : {}),
                        ...(values.zoom
                            ? {
                                  bounds: {
                                      x_min: values.zoom.x[0],
                                      x_max: values.zoom.x[1],
                                      y_min: values.zoom.y[0],
                                      y_max: values.zoom.y[1],
                                  },
                              }
                            : {}),
                        limit: values.zoom ? ZOOMED_POINT_LIMIT : BASE_POINT_LIMIT,
                    })) as MCPIntentMapQueryResponse
                    breakpoint()
                    return response ?? EMPTY_MAP
                },
            },
        ],
    })),

    selectors({
        dateRange: [
            (s) => [s.dateFilter],
            (dateFilter: DateFilter): DateRange => ({
                date_from: dateFilter.dateFrom ?? DEFAULT_DATE_FILTER.dateFrom,
                date_to: dateFilter.dateTo,
            }),
        ],
        dateRangeLabel: [
            (s) => [s.dateFilter],
            (dateFilter: DateFilter): string =>
                dateFilterToText(dateFilter.dateFrom, dateFilter.dateTo, 'Last 7 days') ?? 'Last 7 days',
        ],
        topics: [(s) => [s.map], (map: MCPIntentMapQueryResponse): MCPIntentMapTopic[] => map.topics ?? []],
        points: [(s) => [s.map], (map: MCPIntentMapQueryResponse): MCPIntentMapPoint[] => map.results ?? []],
        totalPoints: [(s) => [s.map], (map: MCPIntentMapQueryResponse): number => map.total_points ?? 0],
        isZoomed: [(s) => [s.zoom], (zoom: ScatterAreaSelection | null): boolean => zoom !== null],
        topicColor: [
            (s) => [s.topicColorSlots],
            (slots: TopicColorSlots) =>
                (topicId: string | null): string =>
                    topicColor(topicId, slots),
        ],
        topicSeries: [
            (s) => [s.topics, s.topicColorSlots],
            (topics: MCPIntentMapTopic[], slots: TopicColorSlots): IntentScatterSeries[] =>
                buildTopicSeries(topics, slots),
        ],
        pointSeries: [
            (s) => [s.points, s.topics, s.topicColorSlots],
            (points: MCPIntentMapPoint[], topics: MCPIntentMapTopic[], slots: TopicColorSlots): IntentScatterSeries[] =>
                buildPointSeries(points, topics, slots),
        ],
        selectedTopic: [
            (s) => [s.topics, s.selectedTopicId],
            (topics: MCPIntentMapTopic[], selectedTopicId: string | null): MCPIntentMapTopic | null =>
                topics.find((topic) => topic.topic_id === selectedTopicId) ?? null,
        ],
        selectedTopicPoints: [
            (s) => [s.points, s.selectedTopicId],
            (points: MCPIntentMapPoint[], selectedTopicId: string | null): MCPIntentMapPoint[] =>
                selectedTopicId === null
                    ? []
                    : points.filter((point) => point.topic_id === selectedTopicId).sort((a, b) => b.calls - a.calls),
        ],
        visibleTopicPoints: [
            (s) => [s.selectedTopicPoints, s.topicPointsShown],
            (selectedTopicPoints: MCPIntentMapPoint[], topicPointsShown: number): MCPIntentMapPoint[] =>
                selectedTopicPoints.slice(0, topicPointsShown),
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        // The scene can mount before /flags answers, so the first load may have been skipped.
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
            if (cache.skippedForFlag && values.featureFlags[FEATURE_FLAGS.MCP_ANALYTICS_INTENT_TOPICS]) {
                actions.loadMap()
            }
        },
        setTool: () => actions.loadMap(),
        setTopicId: () => actions.loadMap(),
        setDateFilter: () => actions.loadMap(),
        setZoom: () => actions.loadMap(),
        hydrateFromUrl: () => actions.loadMap(),
        focusTopic: ({ topicId }) => {
            actions.selectTopic(topicId)
            actions.setTopicId(topicId)
        },
        selectTopic: ({ topicId }) => {
            if (topicId) {
                posthog.capture('mcp analytics intent topic selected', { topic_id: topicId })
            }
        },
    })),

    actionToUrl(({ values }) => {
        const toUrl = (): [string, Record<string, string>] => [
            urls.mcpAnalyticsIntentMap(),
            {
                ...(values.tool ? { tool: values.tool } : {}),
                ...(values.topicId ? { topic: values.topicId } : {}),
                ...(values.dateFilter.dateFrom ? { date_from: values.dateFilter.dateFrom } : {}),
                ...(values.dateFilter.dateTo ? { date_to: values.dateFilter.dateTo } : {}),
            },
        ]
        return { setTool: toUrl, setTopicId: toUrl, setDateFilter: toUrl }
    }),

    urlToAction(({ actions, values }) => ({
        [urls.mcpAnalyticsIntentMap()]: (_, searchParams) => {
            const tool = typeof searchParams.tool === 'string' && searchParams.tool ? searchParams.tool : null
            const topic = typeof searchParams.topic === 'string' && searchParams.topic ? searchParams.topic : null
            const dateFrom = typeof searchParams.date_from === 'string' ? searchParams.date_from : null
            const dateTo = typeof searchParams.date_to === 'string' ? searchParams.date_to : null
            const urlDateFilter: DateFilter = { dateFrom: dateFrom || DEFAULT_DATE_FILTER.dateFrom, dateTo }
            if (
                tool !== values.tool ||
                topic !== values.topicId ||
                urlDateFilter.dateFrom !== values.dateFilter.dateFrom ||
                urlDateFilter.dateTo !== values.dateFilter.dateTo
            ) {
                actions.hydrateFromUrl(tool, topic, urlDateFilter)
            } else {
                actions.loadMap()
            }
        },
    })),

    afterMount(({ values }) => {
        posthog.capture('mcp analytics intent map opened', { tool: values.tool, topic_id: values.topicId })
    }),
])
