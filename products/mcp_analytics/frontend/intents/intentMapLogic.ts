    mapLoading: boolean
    pointSeries: IntentScatterSeries[]
    points: MCPIntentMapPoint[]
    selectedTopic: MCPIntentMapTopic | null
    selectedTopicId: string | null
    selectedTopicPoints: MCPIntentMapPoint[]
    tool: string | null
    topicColor: (topicId: string | null) => string
    topicColorSlots: TopicColorSlots
