export const mcpClusteringLogic = kea<mcpClusteringLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'clustering', 'mcpClusteringLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),
    actions({
        selectCluster: (clusterId: number | null) => ({ clusterId }),
        setSortKey: (sortKey: ClusterSortKey) => ({ sortKey }),
        showAllClusters: true,
        recompute: true,
        startPolling: true,
        stopPolling: true,
        pollSnapshot: true,
    }),
    loaders(({ values }) => ({
        snapshot: [
            EMPTY_SNAPSHOT as MCPIntentClusterSnapshotApi,
            {
                loadSnapshot: async () => {
                    if (!values.currentProjectId) {
                        return EMPTY_SNAPSHOT
                    }
                    const response = await mcpAnalyticsIntentClustersRetrieve(String(values.currentProjectId))
                    return normalizeSnapshot(response)
                },
                triggerRecompute: async () => {
                    if (!values.currentProjectId) {
                        return EMPTY_SNAPSHOT
                    }
                    const response = await mcpAnalyticsIntentClustersRecompute(String(values.currentProjectId))
                    return normalizeSnapshot(response)
                },
            },
        ],
    })),
    reducers({
        selectedClusterId: [
            null as number | null,
            {
                selectCluster: (_, { clusterId }) => clusterId,
            },
        ],
        sortKey: [
            'calls' as ClusterSortKey,
            {
                setSortKey: (_, { sortKey }) => sortKey,
            },
        ],
        allClustersShown: [
            false,
            {
                showAllClusters: () => true,
            },
        ],
    }),
    selectors({
        clusters: [
            (s) => [s.snapshot],
            (snapshot: MCPIntentClusterSnapshotApi): readonly MCPIntentClusterApi[] => snapshot.clusters,
        ],
        sortedClusters: [
            (s) => [s.clusters, s.sortKey],
            (clusters: readonly MCPIntentClusterApi[], sortKey: ClusterSortKey): MCPIntentClusterApi[] => {
                const arr = [...clusters]
                switch (sortKey) {
                    case 'errors':
                        return arr.sort((a, b) => b.error_rate_pct - a.error_rate_pct)
                    case 'entropy':
                        return arr.sort((a, b) => b.routing_entropy - a.routing_entropy)
                    case 'concentration':
                        return arr.sort(
                            (a, b) => (a.tool_distribution[0]?.pct ?? 0) - (b.tool_distribution[0]?.pct ?? 0)
                        )
                    case 'calls':
                    default:
                        return arr.sort((a, b) => b.call_count - a.call_count)
                }
            },
        ],
        // The heatmap rows: sliced after sorting so re-sorting can surface any
        // cluster into the visible set.
        visibleClusters: [
            (s) => [s.sortedClusters, s.allClustersShown],
            (sortedClusters: MCPIntentClusterApi[], allClustersShown: boolean): MCPIntentClusterApi[] =>
                allClustersShown ? sortedClusters : sortedClusters.slice(0, MAX_VISIBLE_CLUSTERS),
        ],
        hiddenClusterCount: [
            (s) => [s.sortedClusters, s.visibleClusters],
            (sortedClusters: MCPIntentClusterApi[], visibleClusters: MCPIntentClusterApi[]): number =>
                sortedClusters.length - visibleClusters.length,
        ],
        // Tools across the whole snapshot, ordered by total calls desc — these are
        // the heatmap columns, capped so a wide tool set can't explode the table.
        toolColumns: [
            (s) => [s.clusters],
            (clusters: readonly MCPIntentClusterApi[]): string[] => {
                const totals = new Map<string, number>()
                for (const cluster of clusters) {
                    for (const entry of cluster.tool_distribution) {
                        totals.set(entry.tool, (totals.get(entry.tool) ?? 0) + entry.count)
                    }
                }
                return [...totals.entries()]
                    .sort((a, b) => b[1] - a[1])
                    .slice(0, MAX_HEATMAP_TOOL_COLUMNS)
                    .map(([tool]) => tool)
            },
        ],
        totalToolCount: [
            (s) => [s.clusters],
            (clusters: readonly MCPIntentClusterApi[]): number => {
                const tools = new Set<string>()
                for (const cluster of clusters) {
                    for (const entry of cluster.tool_distribution) {
                        tools.add(entry.tool)
                    }
                }
                return tools.size
            },
        ],
        // The true number of clusters the run found — the snapshot itself only
        // carries the top MAX_SNAPSHOT_CLUSTERS by call volume, so anything
        // reporting "how many clusters exist" must read this, not clusters.length.
        totalClusterCount: [
            (s) => [s.snapshot],
            (snapshot: MCPIntentClusterSnapshotApi): number =>
                Math.max(snapshot.computed_with?.n_clusters ?? 0, snapshot.clusters.length),
        ],
        selectedCluster: [
            (s) => [s.clusters, s.selectedClusterId],
            (
                clusters: readonly MCPIntentClusterApi[],
                selectedClusterId: number | null
            ): MCPIntentClusterApi | null => {
                if (selectedClusterId === null) {
                    return null
                }
                return clusters.find((c) => c.id === selectedClusterId) ?? null
            },
        ],
        // Scorecard derivations — all from existing aggregate fields.
        concentratedRoutes: [
            (s) => [s.clusters],
            (clusters: readonly MCPIntentClusterApi[]): { focused: number; total: number } => ({
                focused: clusters.filter((c) => (c.tool_distribution[0]?.pct ?? 0) >= 80).length,
                total: clusters.length,
            }),
        ],
        spreadRoutes: [
            (s) => [s.clusters],
            (clusters: readonly MCPIntentClusterApi[]): number =>
                clusters.filter((c) => {
                    const top = c.tool_distribution[0]?.pct ?? 100
                    return c.tool_distribution.length >= 2 && top < 50
                }).length,
        ],
        topErrorRoute: [
            (s) => [s.clusters],
            (clusters: readonly MCPIntentClusterApi[]): MCPIntentClusterApi | null => {
                if (clusters.length === 0) {
                    return null
                }
                // Highest traffic-weighted error count — the cluster that loses the most calls to errors.
                return [...clusters].sort(
                    (a, b) => b.call_count * b.error_rate_pct - a.call_count * a.error_rate_pct
                )[0]
            },
        ],
        isComputing: [
            (s) => [s.snapshot],
            (snapshot: MCPIntentClusterSnapshotApi): boolean => snapshot.status === 'computing',
        ],
        hasSnapshot: [
            (s) => [s.snapshot],
            (snapshot: MCPIntentClusterSnapshotApi): boolean =>
                snapshot.last_computed_at !== null || snapshot.clusters.length > 0,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadSnapshotSuccess: ({ snapshot }) => {
            if (snapshot.status === 'computing') {
                actions.startPolling()
            } else {
                actions.stopPolling()
            }
            if (values.selectedClusterId === null && snapshot.clusters.length > 0) {
                // Auto-select the highest-traffic cluster so the detail pane fills in.
                const top = [...snapshot.clusters].sort((a, b) => b.call_count - a.call_count)[0]
                actions.selectCluster(top.id)
            }
        },
        triggerRecomputeSuccess: ({ snapshot }) => {
            lemonToast.info('Clustering started — this usually takes 30–60 seconds.')
            if (snapshot.status === 'computing') {
                actions.startPolling()
            }
        },
        triggerRecomputeFailure: ({ error }) => {
            lemonToast.error(`Could not start clustering: ${error ?? 'unknown error'}`)
        },
        recompute: () => {
            actions.triggerRecompute()
        },
        startPolling: () => {
            // Keyed add replaces any existing poller, and the disposables plugin
            // pauses it while the tab is hidden — no full-snapshot refetches in
            // background tabs — and cleans it up on unmount.
            cache.disposables.add(() => {
                const intervalId = window.setInterval(() => {
                    actions.pollSnapshot()
                }, POLL_INTERVAL_MS)
                return () => window.clearInterval(intervalId)
            }, 'snapshotPoll')
        },
        stopPolling: () => {
            cache.disposables.dispose('snapshotPoll')
        },
        pollSnapshot: () => {
            actions.loadSnapshot()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSnapshot()
    }),
])
