/**
 * One tool's slice of the intent cluster snapshot, for the tool detail page.
 *
 * Separate from mcpClusteringLogic on purpose: that logic loads the whole
 * snapshot — every cluster plus every tool's pivot — and starts a poll while a
 * run is computing. Mounting it to render one section made every tool page view
 * pay for the entire blob, so this asks the API for the tool's slice instead.
 */
export const mcpToolIntentsLogic = kea<mcpToolIntentsLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'clustering', 'mcpToolIntentsLogic']),
    key((props: MCPToolIntentsLogicProps) => props.toolName),
    props({} as MCPToolIntentsLogicProps),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),
    loaders(({ props, values }) => ({
        snapshot: [
            EMPTY_SNAPSHOT as MCPIntentClusterSnapshotApi,
            {
                loadSnapshot: async () => {
                    if (!values.currentProjectId) {
                        return EMPTY_SNAPSHOT
                    }
                    const response = await mcpAnalyticsIntentClustersRetrieve(String(values.currentProjectId), {
                        tool: props.toolName,
                    })
                    return normalizeSnapshot(response)
                },
            },
        ],
    })),
    selectors({
        tool: [
            (s) => [s.snapshot],
            (snapshot: MCPIntentClusterSnapshotApi): MCPToolPivotApi | null => snapshot.tools?.[0] ?? null,
        ],
        clusters: [
            (s) => [s.snapshot],
            (snapshot: MCPIntentClusterSnapshotApi): readonly MCPIntentClusterApi[] => snapshot.clusters,
        ],
        hasSnapshot: [
            (s) => [s.snapshot],
            (snapshot: MCPIntentClusterSnapshotApi): boolean => snapshot.last_computed_at !== null,
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadSnapshot()
    }),
])
