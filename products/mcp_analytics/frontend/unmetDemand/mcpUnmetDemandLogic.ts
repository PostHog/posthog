import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { actionToUrl, router, urlToAction } from 'kea-router'

import api from 'lib/api'
import { urls } from 'scenes/urls'

import { MCPUnmetDemandItem, NodeKind } from '~/queries/schema/schema-general'

export interface MCPUnmetDemandDateFilter {
    dateFrom: string | null
    dateTo: string | null
}

// 30 days, matching the window behind the Activity tab's report count (ACTIVITY_WINDOW),
// so following that checklist link never shows fewer reports than the count promised.
const DEFAULT_DATE_FILTER: MCPUnmetDemandDateFilter = { dateFrom: '-30d', dateTo: null }

const SEARCH_DEBOUNCE_MS = 300

// One page of reports. Each "Load more" appends the next page.
export const UNMET_DEMAND_PAGE_SIZE = 50

// What the backend labels a report that carried no client identity at all
// (mcp_harness.UNIDENTIFIED_HARNESS_LABEL). Not a client anyone runs, so the table
// renders it as an explicit muted fallback rather than as a client name.
export const UNIDENTIFIED_HARNESS_LABEL = 'Unidentified client'

/** Whether a report tells us nothing about which client filed it.
 *
 * Common, and not the customer's fault: the SDK only stamps `$mcp_client_name` on
 * `$mcp_initialize`, so most `$mcp_missing_capability` events carry no client identity.
 */
export function isUnidentifiedClient(harness: string): boolean {
    return !harness || harness === UNIDENTIFIED_HARNESS_LABEL
}

/** Person email/name the backend packed into the row, for PersonDisplay. */
export function parsePersonProperties(raw: string): Record<string, unknown> {
    try {
        const parsed = JSON.parse(raw || '{}')
        return parsed && typeof parsed === 'object' ? parsed : {}
    } catch {
        return {}
    }
}

