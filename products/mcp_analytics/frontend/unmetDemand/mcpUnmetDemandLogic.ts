export type mcpUnmetDemandLogicType = MakeLogicType<mcpUnmetDemandLogicValues, mcpUnmetDemandLogicActions>

/**
 * The Unmet demand tab: every `$mcp_missing_capability` report an agent filed, newest
 * first. Chronological rather than aggregated — asks are near-unique, so ranking by
 * repeat count would be a wall of ones.
 */
export const mcpUnmetDemandLogic = kea<mcpUnmetDemandLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'unmetDemand', 'mcpUnmetDemandLogic']),

    actions({
        // Declared explicitly so kea-typegen emits no-arg signatures for the loader actions
        // below — the `(_, breakpoint)` loader signature would otherwise force every call
        // site to pass a placeholder argument.
        loadReports: true,
        loadMoreReports: true,
        setSearch: (search: string) => ({ search }),
        setDateFilter: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setHasNext: (hasNext: boolean) => ({ hasNext }),
    }),

    loaders(({ values, actions }) => ({
        reports: [
            [] as MCPUnmetDemandItem[],
            {
                // First page / reset (a search or date change). Replaces the list.
                loadReports: async (_, breakpoint) => {
                    if (values.search) {
                        await breakpoint(SEARCH_DEBOUNCE_MS)
                    }
                    const response = (await api.query({
                        kind: NodeKind.MCPUnmetDemandQuery,
                        dateRange: { date_from: values.dateFilter.dateFrom, date_to: values.dateFilter.dateTo },
                        search: values.search || undefined,
                        limit: UNMET_DEMAND_PAGE_SIZE,
                        offset: 0,
                    })) as { results?: MCPUnmetDemandItem[]; has_next?: boolean }
                    breakpoint()
                    actions.setHasNext(response.has_next ?? false)
                    return response.results ?? []
                },
                // Load more: append the next page at offset = current length.
                loadMoreReports: async () => {
                    // Snapshot the list and the query before the await: if a reset (search or
                    // date change) lands while this page is in flight, merging against the
                    // post-await list would corrupt it, so we both offset and merge from the
                    // snapshot and drop the page entirely if the query moved underneath us.
                    const baseReports = values.reports
                    const { search, dateFilter } = values
                    const response = (await api.query({
                        kind: NodeKind.MCPUnmetDemandQuery,
                        dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo },
                        search: search || undefined,
                        limit: UNMET_DEMAND_PAGE_SIZE,
                        offset: baseReports.length,
                    })) as { results?: MCPUnmetDemandItem[]; has_next?: boolean }
                    if (
                        search !== values.search ||
                        dateFilter.dateFrom !== values.dateFilter.dateFrom ||
                        dateFilter.dateTo !== values.dateFilter.dateTo
                    ) {
                        return values.reports
                    }
                    actions.setHasNext(response.has_next ?? false)
                    return [...baseReports, ...(response.results ?? [])]
                },
            },
        ],
    })),

    reducers({
        search: [
            '',
            {
                setSearch: (_, { search }): string => search,
            },
        ],
        dateFilter: [
            DEFAULT_DATE_FILTER,
            {
                setDateFilter: (_, { dateFrom, dateTo }): MCPUnmetDemandDateFilter => ({ dateFrom, dateTo }),
            },
        ],
        hasNext: [
            false,
            {
                setHasNext: (_, { hasNext }): boolean => hasNext,
                // Hide "Load more" the moment a reset starts, so it isn't shown (disabled,
                // spinning) during the reset; setHasNext restores it when the page resolves.
                loadReports: (): boolean => false,
            },
        ],
    }),

    listeners(({ actions }) => ({
        // Either filter changes the result set — reload from the first page.
        setSearch: () => {
            actions.loadReports()
        },
        setDateFilter: () => {
            actions.loadReports()
        },
    })),

    // Mirror the filters to the URL so they survive a refresh. date_from / date_to are the
    // product's shared window params; search is the same key the Sessions tab uses.
    actionToUrl(({ values }) => {
        const syncUrl = (): [string, Record<string, any>, Record<string, any>, { replace: boolean }] => {
            const { currentLocation } = router.values
            const searchParams = { ...currentLocation.searchParams }
            const params: Record<string, string | null> = {
                search: values.search || null,
                date_from: values.dateFilter.dateFrom,
                date_to: values.dateFilter.dateTo,
            }
            for (const [key, value] of Object.entries(params)) {
                if (value) {
                    searchParams[key] = value
                } else {
                    delete searchParams[key]
                }
            }
            return [currentLocation.pathname, searchParams, currentLocation.hashParams, { replace: true }]
        }
        return { setSearch: syncUrl, setDateFilter: syncUrl }
    }),

    urlToAction(({ actions, values }) => ({
        [urls.mcpAnalyticsUnmetDemand()]: (_, searchParams) => {
            const search = typeof searchParams.search === 'string' ? searchParams.search : ''
            if (search !== values.search) {
                actions.setSearch(search)
            }
            const dateFrom =
                typeof searchParams.date_from === 'string' ? searchParams.date_from : values.dateFilter.dateFrom
            const dateTo = typeof searchParams.date_to === 'string' ? searchParams.date_to : null
            if (dateFrom !== values.dateFilter.dateFrom || dateTo !== values.dateFilter.dateTo) {
                actions.setDateFilter(dateFrom, dateTo)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadReports()
    }),
])
