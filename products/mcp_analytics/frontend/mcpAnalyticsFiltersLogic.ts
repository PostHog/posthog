export type MCPSharedQueryFilters = Required<Pick<HogQLFilters, 'filterTestAccounts' | 'properties'>>

export interface MCPSharedFilterParams {
    properties?: string
    filter_test_accounts?: boolean
}

/** Whether the shared filters narrow anything, so a surface under them shows a subset of the project. */
export function isSharedFilterActive(filters: MCPSharedQueryFilters): boolean {
    return filters.properties.length > 0 || filters.filterTestAccounts
}

/** The shared filters as REST query params. `properties` is JSON-encoded, as the REST endpoints expect. */
export function sharedFilterParams(filters: MCPSharedQueryFilters): MCPSharedFilterParams {
    return {
        properties: filters.properties.length > 0 ? JSON.stringify(filters.properties) : undefined,
        filter_test_accounts: filters.filterTestAccounts || undefined,
    }
}

// Every MCP analytics page hydrates the shared filters from its URL, so a deep link into any tab
// and a tab switch (the scene forwards search params between tabs) land on the same filters.
export const MCP_ANALYTICS_FILTER_ROUTES = [
    urls.mcpAnalyticsActivity(),
    urls.mcpAnalyticsDashboard(),
    urls.mcpAnalyticsSessions(),
    urls.mcpAnalyticsToolQuality(),
    `${urls.mcpAnalyticsToolQuality()}/:toolName`,
    urls.mcpAnalyticsIntentClustering(),
    urls.mcpAnalyticsMissingCapabilities(),
    urls.mcpAnalyticsNotifications(),
]

interface UrlFilters {
    filterTestAccountsOverride: boolean | null
    propertyFilters: AnyPropertyFilter[]
}

function parseUrlFilters(searchParams: Record<string, any>): UrlFilters {
    const rawFilter = searchParams.filter_test_accounts
    return {
        // Absent param leaves the override null (effective value follows the team default).
        filterTestAccountsOverride: rawFilter === undefined ? null : rawFilter === true || rawFilter === 'true',
        propertyFilters: Array.isArray(searchParams.properties) ? searchParams.properties : [],
    }
}

