const TEMPLATE_TITLES = new Set(MCP_RECURRING_REPORTS.map((report) => report.title))

export const mcpRecurringReportsLogic = kea<mcpRecurringReportsLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'notifications', 'mcpRecurringReportsLogic']),
    connect(() => ({
        values: [
            integrationsLogic,
            ['slackIntegrations'],
            userLogic,
            ['user'],
            preflightLogic,
            ['isCloudOrDev'],
            organizationLogic,
            ['currentOrganization'],
            featureFlagLogic,
            ['featureFlags', 'receivedFeatureFlags'],
        ],
    })),
    actions({
        toggleReportEnabled: (reportId: number, enabled: boolean) => ({ reportId, enabled }),
        toggleReportEnabledStarted: (reportId: number) => ({ reportId }),
        toggleReportEnabledSettled: (reportId: number) => ({ reportId }),
        // Optimistic writes go through this rather than the loader's success action, which would also
        // clear `reportsLoading` and hide a reload that is still in flight.
        setReports: (reports: SubscriptionApi[]) => ({ reports }),
        setReportsTruncated: (reportsTruncated: boolean) => ({ reportsTruncated }),
        deleteReport: (report: SubscriptionApi) => ({ report }),
        createWeeklyReport: true,
        createWeeklyReportStarted: true,
        createWeeklyReportSucceeded: (report: SubscriptionApi) => ({ report }),
        createWeeklyReportFailed: (message: string) => ({ message }),
    }),
    loaders(({ actions }) => ({
        reports: [
            [] as SubscriptionApi[],
            {
                loadReports: async (): Promise<SubscriptionApi[]> => {
                    // `search` matches the prompt server-side, so the rows that cross the wire are
                    // already the MCP ones rather than every AI report the project has. It also spans
                    // title and insight/dashboard names, so `isMCPRecurringReport` still runs as the
                    // precise test — a report merely *titled* "$mcp_" is not one.
                    const response = await subscriptionsList(String(getCurrentTeamId()), {
                        resource_type: SubscriptionsListResourceType.AiPrompt,
                        search: MCP_PROPERTY_PREFIX,
                        limit: AI_REPORT_LIST_LIMIT,
                    })
                    actions.setReportsTruncated(!!response.next)
                    return response.results.filter(
                        (subscription) => !subscription.deleted && isMCPRecurringReport(subscription)
                    )
                },
            },
        ],
    })),
    reducers({
        reports: {
            setReports: (_: SubscriptionApi[], { reports }: { reports: SubscriptionApi[] }) => reports,
        },
        pendingToggleIds: [
            {} as Record<number, true>,
            {
                toggleReportEnabledStarted: (state, { reportId }) => ({ ...state, [reportId]: true }),
                toggleReportEnabledSettled: (state, { reportId }) => {
                    const nextState = { ...state }
                    delete nextState[reportId]
                    return nextState
                },
            },
        ],
        reportsFailed: [
            false,
            {
                loadReports: () => false,
                loadReportsSuccess: () => false,
                loadReportsFailure: () => true,
            },
        ],
        reportsTruncated: [
            false,
            {
                setReportsTruncated: (_, { reportsTruncated }) => reportsTruncated,
            },
        ],
        weeklyReportSubmission: [
            { status: 'idle' } as WeeklyReportSubmission,
            {
                createWeeklyReportStarted: (): WeeklyReportSubmission => ({ status: 'creating' }),
                createWeeklyReportSucceeded: (_, { report }): WeeklyReportSubmission => ({ status: 'created', report }),
                createWeeklyReportFailed: (_, { message }): WeeklyReportSubmission => ({ status: 'failed', message }),
            },
        ],
        // The list loads when the tab mounts; without this the first render would flash the empty state.
        reportsLoaded: [
            false,
            {
                loadReportsSuccess: () => true,
                loadReportsFailure: () => true,
            },
        ],
    }),
    selectors({
        // A saved report is tied back to the template that offers it by title, which is what the
        // template's deep link sets. Renaming one moves it to "other" rather than losing it.
        reportsByTemplateTitle: [
            (s) => [s.reports],
            (reports: SubscriptionApi[]): Record<string, SubscriptionApi[]> =>
                Object.fromEntries(
                    MCP_RECURRING_REPORTS.map((report) => [
                        report.title,
                        reports.filter((saved) => saved.title === report.title),
                    ])
                ),
        ],
        otherReports: [
            (s) => [s.reports],
            (reports: SubscriptionApi[]): SubscriptionApi[] =>
                reports.filter((saved) => !saved.title || !TEMPLATE_TITLES.has(saved.title)),
        ],
        // The destination someone picked for their last report is the best guess for the next one.
        // Before that, a connected Slack workspace is the likeliest channel, and email needs no setup.
        // Null until all three inputs load, so an early click gets the form's own default, not a guess.
        defaultTargetType: [
            (s) => [s.reports, s.reportsLoaded, s.user, s.slackIntegrations],
            (
                reports: SubscriptionApi[],
                reportsLoaded: boolean,
                user: UserType | null,
                slackIntegrations: IntegrationType[] | undefined
            ): SubscriptionTargetEnumApi | null => {
                if (!reportsLoaded || !user || slackIntegrations === undefined) {
                    return null
                }
                // The API lists newest first, so the first match is the most recent.
                const lastOwnReport = reports.find((report) => report.created_by?.uuid === user.uuid)
                if (lastOwnReport) {
                    return lastOwnReport.target_type
                }
                return slackIntegrations.length ? SubscriptionTargetEnumApi.Slack : SubscriptionTargetEnumApi.Email
            },
        ],
        weeklyReportOffer: [
            (s) => [
                s.isCloudOrDev,
                s.featureFlags,
                s.receivedFeatureFlags,
                s.currentOrganization,
                s.user,
                s.reports,
                s.reportsLoaded,
                s.reportsFailed,
                s.reportsTruncated,
                s.weeklyReportSubmission,
            ],
            (
                isCloudOrDev: boolean | undefined,
                featureFlags: FeatureFlagsSet,
                receivedFeatureFlags: boolean,
                currentOrganization: OrganizationType | null,
                user: UserType | null,
                reports: SubscriptionApi[],
                reportsLoaded: boolean,
                reportsFailed: boolean,
                reportsTruncated: boolean,
                weeklyReportSubmission: WeeklyReportSubmission
            ): WeeklyReportOffer =>
                resolveWeeklyReportOffer({
                    isCloudOrDev,
                    aiFlagEnabled: receivedFeatureFlags ? !!featureFlags[FEATURE_FLAGS.SUBSCRIPTION_AI_PROMPT] : null,
                    aiConsentApproved: currentOrganization
                        ? !!currentOrganization.is_ai_data_processing_approved
                        : null,
                    userEmail: user?.email ?? null,
                    reports: !reportsLoaded ? 'loading' : reportsFailed || reportsTruncated ? 'unknown' : reports,
                    submission: weeklyReportSubmission,
                }),
        ],
    }),
    listeners(({ actions, values }) => ({
        createWeeklyReport: async () => {
            const offer = values.weeklyReportOffer
            // The same union drives the UI, so a double click and every closed gate end here.
            if (offer.state !== 'ready' && offer.state !== 'failed') {
                return
            }
            // Dispatched before the await, so a second click sees `creating`.
            actions.createWeeklyReportStarted()

            let report: SubscriptionApi
            try {
                report = await subscriptionsCreate(
                    String(getCurrentTeamId()),
                    weeklyReportPayload(TOOL_HEALTH_REPORT, offer.email, dayjs())
                )
            } catch (error) {
                const message = createErrorMessage(error)
                actions.createWeeklyReportFailed(message)
                posthog.captureRaw('mcp analytics weekly report failed', {
                    mcp_report_template: TOOL_HEALTH_REPORT.key,
                    error_status: error instanceof ApiError ? (error.status ?? null) : null,
                    error_message: message,
                })
                // A request that failed in transit may still have saved the report. Reloading turns
                // that case into `has-report` instead of offering a retry that would duplicate it.
                if (createMayHaveSucceeded(error)) {
                    actions.loadReports()
                }
                return
            }
            actions.setReports([report, ...values.reports])
            actions.createWeeklyReportSucceeded(report)
            posthog.captureRaw('subscription created', {
                creation_source: 'mcp_analytics_one_click',
                resource_type: 'ai',
                subscription_id: report.id,
                target_type: report.target_type,
                mcp_report_template: TOOL_HEALTH_REPORT.key,
            })
        },
        toggleReportEnabled: async ({ reportId, enabled }) => {
            if (values.pendingToggleIds[reportId]) {
                return
            }
            const target = values.reports.find((report) => report.id === reportId)
            if (!target) {
                return
            }
            actions.toggleReportEnabledStarted(reportId)

            const applyEnabled = (next: boolean): void => {
                actions.setReports(
                    values.reports.map((report) => (report.id === reportId ? { ...report, enabled: next } : report))
                )
            }

            applyEnabled(enabled)
            // `toggleSubscriptionEnabled` never rejects — it toasts the failure itself and reports
            // false — so the revert hangs off the return value rather than a catch.
            if (!(await toggleSubscriptionEnabled(reportId, enabled))) {
                applyEnabled(!enabled)
            }
            actions.toggleReportEnabledSettled(reportId)
        },
        deleteReport: async ({ report }) => {
            // Re-insert just this row at the position it held, rather than replaying a whole-list
            // snapshot: a second delete may have landed in between, and replaying would resurrect what
            // it removed.
            const removedIndex = values.reports.findIndex((item) => item.id === report.id)
            const restore = (): void => {
                if (values.reports.some((item) => item.id === report.id)) {
                    return
                }
                const restored = [...values.reports]
                restored.splice(Math.min(removedIndex, restored.length), 0, report)
                actions.setReports(restored)
            }

            actions.setReports(values.reports.filter((item) => item.id !== report.id))

            // `deleteWithUndo` swallows its own API errors and resolves without calling back, so a
            // failed delete is only detectable by the callback never firing — otherwise the row stays
            // optimistically gone while the report is alive and still delivering.
            let callbackFired = false
            await deleteWithUndo({
                endpoint: api.subscriptions.determineDeleteEndpoint(),
                object: { id: report.id, name: report.title ?? 'Report' },
                callback: (undo) => {
                    callbackFired = true
                    if (undo) {
                        restore()
                    }
                },
            })
            if (!callbackFired) {
                restore()
            }
        },
    })),
])
