import { MakeLogicType, actions, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import api from 'lib/api'
import posthog from 'lib/posthog-typed'
import { deleteWithUndo } from 'lib/utils/deleteWithUndo'
import { getCurrentTeamId } from 'lib/utils/getAppContext'

import { toggleSubscriptionEnabled } from 'products/subscriptions/frontend/components/Subscriptions/toggleSubscriptionEnabled'
import { subscriptionsDeliveriesList, subscriptionsList } from 'products/subscriptions/frontend/generated/api'
import { SubscriptionApi, SubscriptionsListResourceType } from 'products/subscriptions/frontend/generated/api.schemas'

// Caps the AI-report page this pulls, so a project with a lot of them can't make the tab fetch the
// lot. The MCP ones are a subset of that; the rest stay manageable from the subscriptions page.
const AI_REPORT_LIST_LIMIT = 200
// A status costs one request per report, so only the first few get one — the same ones at the top of
// the list, since both follow the API's ordering.
const MAX_STATUS_LOOKUPS = 10

/**
 * A Subscription has no field saying which product created it — `resource_type` is derived from which
 * of insight/dashboard/prompt is set, and an `ai_prompt` one carries nothing but free text. So "is this
 * an MCP report?" is answered the way the instant-alert list answers it for hog functions: by what the
 * thing actually queries. Every report the cards create names `$mcp_*` properties, and a hand-written
 * one reporting on MCP data has to name them too.
 *
 * The cost of matching on content is that editing those property names out of a prompt drops it off
 * this tab. The alternative is a provenance column on a model owned outside this product, which would
 * also show nothing for the reports that already exist.
 */
const MCP_PROPERTY_PREFIX = '$mcp_'

export function isMCPRecurringReport(subscription: Pick<SubscriptionApi, 'prompt'>): boolean {
    return (subscription.prompt ?? '').includes(MCP_PROPERTY_PREFIX)
}

/** Outcome of a report's last run, for the reports we look one up for. */
export type MCPReportDeliveryStatus = 'completed' | 'failed' | 'skipped' | 'starting'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface mcpRecurringReportsLogicValues {
    deliveryStatuses: Record<number, MCPReportDeliveryStatus>
    deliveryStatusesLoading: boolean
    pendingToggleIds: Record<number, true>
    reports: SubscriptionApi[]
    reportsFailed: boolean
    reportsLoaded: boolean
    reportsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface mcpRecurringReportsLogicActions {
    deleteReport: (report: SubscriptionApi) => {
        report: SubscriptionApi
    }
    loadDeliveryStatuses: (reports: SubscriptionApi[]) => any
    loadDeliveryStatusesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadDeliveryStatusesSuccess: (
        deliveryStatuses: Record<number, MCPReportDeliveryStatus>,
        payload?: any
    ) => {
        deliveryStatuses: Record<number, MCPReportDeliveryStatus>
        payload?: any
    }
    loadReports: () => any
    loadReportsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadReportsSuccess: (
        reports: SubscriptionApi[],
        payload?: any
    ) => {
        reports: SubscriptionApi[]
        payload?: any
    }
    setReports: (reports: SubscriptionApi[]) => {
        reports: SubscriptionApi[]
    }
    toggleReportEnabled: (
        reportId: number,
        enabled: boolean
    ) => {
        enabled: boolean
        reportId: number
    }
    toggleReportEnabledSettled: (reportId: number) => {
        reportId: number
    }
    toggleReportEnabledStarted: (reportId: number) => {
        reportId: number
    }
}

export type mcpRecurringReportsLogicType = MakeLogicType<
    mcpRecurringReportsLogicValues,
    mcpRecurringReportsLogicActions
>

export const mcpRecurringReportsLogic = kea<mcpRecurringReportsLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'notifications', 'mcpRecurringReportsLogic']),
    actions({
        toggleReportEnabled: (reportId: number, enabled: boolean) => ({ reportId, enabled }),
        toggleReportEnabledStarted: (reportId: number) => ({ reportId }),
        toggleReportEnabledSettled: (reportId: number) => ({ reportId }),
        // Optimistic writes go through this rather than the loader's success action, which would also
        // clear `reportsLoading` and hide a reload that is still in flight.
        setReports: (reports: SubscriptionApi[]) => ({ reports }),
        deleteReport: (report: SubscriptionApi) => ({ report }),
    }),
    loaders(() => ({
        reports: [
            [] as SubscriptionApi[],
            {
                loadReports: async (): Promise<SubscriptionApi[]> => {
                    // No server-side filter reaches `prompt` — the endpoint's `search` covers title and
                    // insight/dashboard names only — so the MCP ones are picked out here.
                    const response = await subscriptionsList(String(getCurrentTeamId()), {
                        resource_type: SubscriptionsListResourceType.AiPrompt,
                        limit: AI_REPORT_LIST_LIMIT,
                    })
                    return response.results.filter(
                        (subscription) => !subscription.deleted && isMCPRecurringReport(subscription)
                    )
                },
            },
        ],
        deliveryStatuses: [
            {} as Record<number, MCPReportDeliveryStatus>,
            {
                loadDeliveryStatuses: async (
                    reports: SubscriptionApi[]
                ): Promise<Record<number, MCPReportDeliveryStatus>> => {
                    const teamId = String(getCurrentTeamId())
                    const entries = await Promise.all(
                        reports.slice(0, MAX_STATUS_LOOKUPS).map(async (report) => {
                            try {
                                // Cursor-paginated newest first, so the head row is the last run.
                                const response = await subscriptionsDeliveriesList(teamId, report.id)
                                const status = response.results[0]?.status
                                return status ? ([report.id, status as MCPReportDeliveryStatus] as const) : null
                            } catch {
                                // A status decorates a row we can already render; failing to read one
                                // must not take down the list.
                                return null
                            }
                        })
                    )
                    return Object.fromEntries(entries.filter((entry) => entry !== null))
                },
            },
        ],
    })),
    reducers({
        reports: {
            setReports: (_: SubscriptionApi[], { reports }: { reports: SubscriptionApi[] }) => reports,
        },
        pendingToggleIds: [
            {} as Record<number, true>,
            {
                toggleReportEnabledStarted: (state, { reportId }) => ({ ...state, [reportId]: true }),
                toggleReportEnabledSettled: (state, { reportId }) => {
                    const nextState = { ...state }
                    delete nextState[reportId]
                    return nextState
                },
            },
        ],
        reportsFailed: [
            false,
            {
                loadReports: () => false,
                loadReportsSuccess: () => false,
                loadReportsFailure: () => true,
            },
        ],
        // The list loads when the tab mounts; without this the first render would flash the empty state.
        reportsLoaded: [
            false,
            {
                loadReportsSuccess: () => true,
                loadReportsFailure: () => true,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        loadReportsSuccess: ({ reports }) => {
            if (reports.length) {
                actions.loadDeliveryStatuses(reports)
            }
        },
        toggleReportEnabled: async ({ reportId, enabled }) => {
            if (values.pendingToggleIds[reportId]) {
                return
            }
            const target = values.reports.find((report) => report.id === reportId)
            if (!target) {
                return
            }
            actions.toggleReportEnabledStarted(reportId)

            const applyEnabled = (next: boolean): void => {
                actions.setReports(
                    values.reports.map((report) => (report.id === reportId ? { ...report, enabled: next } : report))
                )
            }

            applyEnabled(enabled)
            try {
                if (!(await toggleSubscriptionEnabled(reportId, enabled))) {
                    // toggleSubscriptionEnabled surfaces its own failure to the user.
                    applyEnabled(!enabled)
                }
            } catch (error) {
                applyEnabled(!enabled)
                lemonToast.error('Failed to update report')
                posthog.captureException(error, { action: 'toggle-mcp-analytics-recurring-report' })
            } finally {
                actions.toggleReportEnabledSettled(reportId)
            }
        },
        deleteReport: async ({ report }) => {
            const previousReports = values.reports
            actions.setReports(values.reports.filter((item) => item.id !== report.id))
            try {
                await deleteWithUndo({
                    endpoint: api.subscriptions.determineDeleteEndpoint(),
                    object: { id: report.id, name: report.title ?? 'Report' },
                    callback: (undo) => {
                        if (undo) {
                            actions.setReports(previousReports)
                        }
                    },
                })
            } catch (error) {
                actions.setReports(previousReports)
                lemonToast.error('Failed to delete report')
                posthog.captureException(error, { action: 'delete-mcp-analytics-recurring-report' })
            }
        },
    })),
])
