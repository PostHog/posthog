// A ceiling on what one tab render will pull. The server-side `search` below already narrows to MCP
// reports, so reaching this means a project with hundreds of them — at which point the list is the
// wrong tool anyway and `reportsTruncated` says so rather than quietly dropping the tail.
export const AI_REPORT_LIST_LIMIT = 200

/**
 * A Subscription has no field saying which product created it — `resource_type` is derived from which
 * of insight/dashboard/prompt is set, and an `ai_prompt` one carries nothing but free text. So "is this
 * an MCP report?" is answered the way the instant-alert list answers it for hog functions: by what the
 * thing actually queries. Every report the cards create names `$mcp_*` properties, and a hand-written
 * one reporting on MCP data has to name them too.
 *
 * The cost of matching on content is that editing those property names out of a prompt drops it off
 * this tab. The alternative is a provenance column on a model owned outside this product, which would
 * also show nothing for the reports that already exist.
 */
const MCP_PROPERTY_PREFIX = '$mcp_'

export function isMCPRecurringReport(subscription: Pick<SubscriptionApi, 'prompt'>): boolean {
    return (subscription.prompt ?? '').includes(MCP_PROPERTY_PREFIX)
}

