export const mcpSetupModeLogic = kea<mcpSetupModeLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'setupMode', 'mcpSetupModeLogic']),
    connect(() => ({
        values: [
            router,
            ['searchParams', 'location'],
            featureFlagLogic,
            ['featureFlags'],
            mcpAnalyticsOnboardingLogic,
            ['signals', 'onboardingState'],
            teamLogic,
            ['currentProjectId'],
            mcpAnalyticsSetupLogic,
            ['agentPrompt'],
        ],
        actions: [
            productSetupStatusLogic({ productKey: ProductKey.MCP_ANALYTICS }),
            ['reportSetupInteraction'],
            mcpAnalyticsOnboardingLogic,
            ['loadSignals'],
        ],
    })),
    actions({
        openSetupMode: (path: MCPSetupPath, trigger: MCPSetupTrigger) => ({ path, trigger }),
        goToUsefulStep: true,
        exitSetupMode: (reason: MCPSetupExitReason) => ({ reason }),
        askPostHogAI: (prompt: string) => ({ prompt }),
    }),
    loaders(({ values }) => ({
        recentCalls: [
            null as MCPActivityRecentCallApi[] | null,
            {
                loadRecentCalls: async (_: void, breakpoint): Promise<MCPActivityRecentCallApi[] | null> => {
                    // The overview resolves each call's client to a harness label and pulls the readable
                    // message out of a failed call's response, both of which only the backend knows how to do.
                    const overview = await mcpAnalyticsSessionsActivityOverview(String(values.currentProjectId))
                    breakpoint()
                    return overview.recent_calls.slice(0, RECENT_CALLS)
                },
            },
        ],
    })),
    reducers({
        recentCallsFailed: [
            false,
            {
                loadRecentCallsSuccess: () => false,
                loadRecentCallsFailure: () => true,
            },
        ],
    }),
    selectors({
        isEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: Record<string, unknown>): boolean => !!featureFlags[FEATURE_FLAGS.MCP_ANALYTICS_SETUP_MODE],
        ],
        setupPath: [
            (s) => [s.isEnabled, s.searchParams],
            (isEnabled: boolean, searchParams: Record<string, unknown>): MCPSetupPath | null =>
                isEnabled ? parseSetupPath(searchParams[SETUP_PARAM]) : null,
        ],
        isOpen: [(s) => [s.setupPath], (setupPath: MCPSetupPath | null): boolean => setupPath !== null],
        /** `null` until the onboarding signals answer, so a reload never flashes the wrong step. */
        step: [
            (s) => [s.setupPath, s.signals, s.searchParams],
            (
                setupPath: MCPSetupPath | null,
                signals: { hasToolCall: boolean } | null,
                searchParams: Record<string, unknown>
            ): MCPSetupStep | null => {
                if (!setupPath || !signals) {
                    return null
                }
                const requested = searchParams[SETUP_STEP_PARAM]
                return setupStepFor({
                    hasToolCall: signals.hasToolCall,
                    requestedStep: typeof requested === 'string' ? requested : null,
                })
            },
        ],
        viewedStep: [
            (s) => [s.setupPath, s.step],
            (setupPath: MCPSetupPath | null, step: MCPSetupStep | null): string | null =>
                setupPath && step ? `${setupPath}:${step}` : null,
        ],
        connectState: [(s) => [s.onboardingState], connectStateFor],
    }),
    listeners(({ actions, values }) => ({
        reportSetupInteraction: ({ action, preview }) => {
            if (preview) {
                return
            }
            if (action === 'wizard command copied') {
                actions.openSetupMode('wizard', 'wizard_copy')
            } else if (action === 'agent prompt copied') {
                actions.openSetupMode('agent', 'agent_copy')
            }
        },
        openSetupMode: ({ path, trigger }) => {
            if (!values.isEnabled || values.isOpen) {
                return
            }
            tracking.opened = true
            capture('mcp analytics setup mode opened', { path, trigger })
            router.actions.push(values.location.pathname, {
                ...withoutSetupParams(values.searchParams),
                [SETUP_PARAM]: path,
            })
        },
        askPostHogAI: ({ prompt }) => {
            // The side panel opens under the fullscreen setup mode, so close setup mode first.
            actions.exitSetupMode('ask_ai')
            sidePanelStateLogic.actions.openSidePanel(SidePanelTab.Max, autoRunMaxPrompt(prompt))
        },
        goToUsefulStep: () => {
            router.actions.replace(values.location.pathname, { ...values.searchParams, [SETUP_STEP_PARAM]: 'useful' })
        },
        exitSetupMode: ({ reason }) => {
            if (!values.isOpen) {
                return
            }
            capture('mcp analytics setup mode exited', { path: values.setupPath, step: values.step, reason })
            tracking.opened = false
            tracking.lastViewedStep = null
            const searchParams = withoutSetupParams(values.searchParams)
            if (reason === 'finished' || reason === 'ask_ai') {
                router.actions.push(urls.mcpAnalyticsActivity(), searchParams)
            } else {
                router.actions.replace(values.location.pathname, searchParams)
            }
        },
    })),
    subscriptions(({ actions, values, cache }) => ({
        isOpen: (isOpen: boolean) => {
            // On the window rather than the modal, because the modal only hears keys while focus is inside
            // it, and a step change replaces the focused button.
            if (isOpen) {
                cache.disposables.add(() => {
                    const onKeyDown = (event: KeyboardEvent): void => {
                        if (event.key === 'Escape' && !event.defaultPrevented) {
                            actions.exitSetupMode('escape')
                        }
                    }
                    window.addEventListener('keydown', onKeyDown)
                    return () => window.removeEventListener('keydown', onKeyDown)
                }, 'escape')
            } else {
                cache.disposables.dispose('escape')
            }
            // Anything that opens setup mode without `openSetupMode` came in through the URL: a reload,
            // a shared link, or browser history.
            if (isOpen && !tracking.opened) {
                tracking.opened = true
                capture('mcp analytics setup mode opened', { path: values.setupPath, trigger: 'url' })
            }
        },
        step: (step: MCPSetupStep | null) => {
            cache.disposables.dispose('setupPoll')
            if (step === 'connect') {
                cache.disposables.add(() => {
                    const id = window.setInterval(() => actions.loadSignals(), CONNECT_POLL_MS)
                    return () => clearInterval(id)
                }, 'setupPoll')
            } else if (step === 'first-call') {
                actions.loadRecentCalls()
                cache.disposables.add(() => {
                    const id = window.setInterval(() => actions.loadRecentCalls(), FIRST_CALL_POLL_MS)
                    return () => clearInterval(id)
                }, 'setupPoll')
            }
        },
        viewedStep: (viewedStep: string | null) => {
            if (viewedStep && viewedStep !== tracking.lastViewedStep) {
                tracking.lastViewedStep = viewedStep
                capture('mcp analytics setup mode step viewed', { step: values.step, path: values.setupPath })
            }
        },
    })),
])
