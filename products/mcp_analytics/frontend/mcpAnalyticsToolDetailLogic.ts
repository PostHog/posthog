export const mcpAnalyticsToolDetailLogic = kea<mcpAnalyticsToolDetailLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'mcpAnalyticsToolDetailLogic']),
    key((props: MCPAnalyticsToolDetailLogicProps) => props.toolName),
    props({} as MCPAnalyticsToolDetailLogicProps),

    connect(() => ({
        values: [mcpAnalyticsFiltersLogic, ['queryFilters as sharedQueryFilters']],
    })),

    actions({
        setDateFilter: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setPinnedInterval: (interval: IntervalType | null) => ({ interval }),
        loadAllSections: true,
        openExample: (example: ExampleCall | null) => ({ example }),
    }),

    reducers({
        dateFilter: [
            DEFAULT_DATE_FILTER,
            {
                setDateFilter: (_, { dateFrom, dateTo }): DateFilter => ({ dateFrom, dateTo }),
            },
        ],
        // Grouping picked on the Tool quality tab and carried here in the URL; null follows the
        // auto-choice for the window. This page has no picker of its own.
        pinnedInterval: [
            null as IntervalType | null,
            {
                setPinnedInterval: (_, { interval }): IntervalType | null => interval,
            },
        ],
        selectedExample: [
            null as ExampleCall | null,
            {
                openExample: (_, { example }): ExampleCall | null => example,
            },
        ],
    }),

    loaders(({ props, values }) => ({
        topModelRows: [
            [] as ResultRows,
            {
                loadTopModelRows: async (_: void, breakpoint): Promise<ResultRows> => {
                    const response = (await api.query(
                        toolTopModelsQuery(props.toolName, values.dateRange, values.sharedQueryFilters)
                    )) as { results?: unknown[][] }
                    breakpoint()
                    return (response.results ?? []) as ResultRows
                },
            },
        ],
        journey: [
            { paths: [], totalSessions: 0, errorSessions: 0 } as ToolJourney,
            {
                loadJourney: async (_: void, breakpoint): Promise<ToolJourney> => {
                    const response = (await api.query(
                        toolJourneyQuery(props.toolName, values.dateRange, values.sharedQueryFilters)
                    )) as { results?: unknown[][] }
                    breakpoint()
                    return toToolJourney(response.results)
                },
            },
        ],
        examples: [
            { errored: [], slow: [], succeeded: [] } as ToolExamples,
            {
                loadExamples: async (_: void, breakpoint): Promise<ToolExamples> => {
                    const kinds: ExampleKind[] = ['errored', 'slow', 'succeeded']
                    const responses = (await Promise.all(
                        kinds.map((kind) =>
                            api.query(
                                toolExamplesQuery(kind, props.toolName, values.dateRange, values.sharedQueryFilters)
                            )
                        )
                    )) as { results?: unknown[][] }[]
                    breakpoint()
                    return {
                        errored: toExampleCalls(responses[0].results),
                        slow: toExampleCalls(responses[1].results),
                        succeeded: toExampleCalls(responses[2].results),
                    }
                },
            },
        ],
        summary: [
            null as ToolSummary | null,
            {
                loadSummary: async (_: void, breakpoint): Promise<ToolSummary | null> => {
                    const response = (await api.query({
                        kind: NodeKind.MCPToolStatsQuery,
                        toolName: props.toolName,
                        dateRange: values.dateRange,
                        ...values.sharedQueryFilters,
                    })) as { results?: MCPToolStatsItem[] }
                    breakpoint()
                    const row = response?.results?.[0]
                    if (!row) {
                        return null
                    }
                    return {
                        calls: row.calls,
                        errors: row.errors,
                        p50_ms: row.p50_ms,
                        p95_ms: row.p95_ms,
                        users: row.users,
                        conversations: row.conversations,
                        total_calls: row.total_calls,
                        total_conversations: row.total_conversations,
                    }
                },
            },
        ],
        descriptions: [
            [] as DescriptionRevision[],
            {
                loadDescriptions: async (_: void, breakpoint): Promise<DescriptionRevision[]> => {
                    const response = (await api.query({
                        kind: NodeKind.MCPToolDescriptionsQuery,
                        toolName: props.toolName,
                        dateRange: values.dateRange,
                        ...values.sharedQueryFilters,
                    })) as { results?: MCPToolDescriptionItem[] }
                    breakpoint()
                    return (response?.results ?? []).map((r) => ({
                        description: r.description,
                        last_seen: r.last_seen,
                    }))
                },
            },
        ],
        dailyStats: [
            [] as DailyToolStat[],
            {
                // Guarded with breakpoint: dailyChartData builds its bucket keys from the *live* interval,
                // so a superseded response fetched at a different interval (e.g. day → hour on a fast
                // back/forward) would otherwise land and collapse a day's rows into one hourly bucket.
                loadDailyStats: async (_: void, breakpoint): Promise<DailyToolStat[]> => {
                    const response = (await api.query({
                        kind: NodeKind.MCPToolDailyStatsQuery,
                        toolName: props.toolName,
                        dateRange: values.dateRange,
                        interval: values.interval,
                        ...values.sharedQueryFilters,
                    })) as { results?: MCPToolDailyStatItem[] }
                    breakpoint()
                    return (response?.results ?? []).map((r) => ({
                        day: r.day,
                        calls: r.calls,
                        errors: r.errors,
                        p50: r.p50,
                        p95: r.p95,
                        users: r.users,
                        sessions: r.sessions,
                    }))
                },
            },
        ],
        byHarnessRows: [
            [] as ResultRows,
            {
                // Server-resolved harness labels via the same runner as the dashboard (scoped to this
                // tool's new-SDK calls by toolName), so the pill matches the dashboard's bucketing exactly.
                loadByHarnessRows: async (_: void, breakpoint): Promise<ResultRows> => {
                    const response = (await api.query({
                        kind: NodeKind.MCPHarnessBreakdownQuery,
                        toolName: props.toolName,
                        dateRange: values.dateRange,
                        ...values.sharedQueryFilters,
                    })) as { results?: MCPHarnessBreakdownItem[] }
                    breakpoint()
                    return (response?.results ?? []).map((r) => [
                        r.harness,
                        r.total_calls,
                        r.errors,
                        r.error_rate_pct,
                        r.sessions,
                        r.harness_sessions ?? null,
                    ])
                },
            },
        ],
        topUserRows: [
            [] as ResultRows,
            {
                // The person tuple is rebuilt into the [distinct_id, _, properties] shape renderPersonCell expects.
                loadTopUserRows: async (_: void, breakpoint): Promise<ResultRows> => {
                    const response = (await api.query({
                        kind: NodeKind.MCPToolTopUsersQuery,
                        toolName: props.toolName,
                        dateRange: values.dateRange,
                        ...values.sharedQueryFilters,
                    })) as { results?: MCPToolTopUserItem[] }
                    breakpoint()
                    return (response?.results ?? []).map((r) => [
                        [r.distinct_id, '', r.person_properties],
                        r.calls,
                        r.errors,
                        r.error_rate_pct,
                        r.harnesses,
                        r.last_seen,
                    ])
                },
            },
        ],
    })),

    selectors({
        toolName: [() => [(_, props) => props.toolName], (toolName: string) => toolName],

        dailyChartData: [
            (s) => [s.dailyStats, s.dateFilter, s.interval, teamLogic.selectors.timezone],
            (
                dailyStats: DailyToolStat[],
                dateFilter: DateFilter,
                interval: IntervalType,
                timezone: string
            ): DailyChartData => {
                const bucketKeys = buildBucketKeys(dateFilter.dateFrom, dateFilter.dateTo, timezone, interval)
                return buildDailyChartData(dailyStats, bucketKeys)
            },
        ],

        // The trend charts and sparklines dash the final segment when it is the current, still-
        // collecting interval, so a partial period doesn't read as a fall in calls or a latency win.
        incompleteTail: [
            (s) => [s.dailyChartData, s.interval, teamLogic.selectors.timezone],
            (dailyChartData: DailyChartData, interval: IntervalType, timezone: string): boolean =>
                lastBucketIsInProgress(dailyChartData.labels, timezone, interval),
        ],

        // Grouping interval for the daily series, matching the query's dateTrunc: the interval pinned on
        // the Tool quality tab, else the auto-choice so a sub-day window buckets by hour/minute instead
        // of collapsing to one day point.
        interval: [
            (s) => [s.dateFilter, s.pinnedInterval, teamLogic.selectors.timezone],
            (dateFilter: DateFilter, pinnedInterval: IntervalType | null, timezone: string): IntervalType =>
                resolveInterval(dateFilter.dateFrom, dateFilter.dateTo, timezone, pinnedInterval),
        ],

        // Resolve the `dateFilter` state (camelCase, nullable, may be relative like '-30d') into the
        // absolute snake_case `DateRange` the query API takes. Done once so every section queries the
        // exact same window — a relative '-Nd' would re-resolve per section and drift after midnight.
        dateRange: [
            (s) => [s.dateFilter, teamLogic.selectors.timezone],
            (dateFilter: DateFilter, timezone: string): DateRange => {
                const to = dateStringToDayJs(dateFilter.dateTo, timezone) ?? dayjs().tz(timezone)
                const from =
                    dateStringToDayJs(dateFilter.dateFrom, timezone) ?? dayjs().tz(timezone).subtract(30, 'day')
                return { date_from: from.toISOString(), date_to: to.toISOString() }
            },
        ],

        dateRangeLabel: [
            (s) => [s.dateFilter],
            (dateFilter: DateFilter): string =>
                dateFilterToText(dateFilter.dateFrom, dateFilter.dateTo, 'the selected range') ?? 'the selected range',
        ],
        // The full page sits under Tool quality, so its trail leads back to that list.
        breadcrumbs: [
            (s, p) => [s.dateFilter, s.pinnedInterval, p.toolName],
            (dateFilter: DateFilter, pinnedInterval: IntervalType | null, toolName: string): Breadcrumb[] => [
                { key: 'mcp-analytics', name: 'MCP analytics', path: urls.mcpAnalytics(), iconType: 'mcp_analytics' },
                {
                    key: 'mcp-analytics-tool-quality',
                    name: 'Tool quality',
                    path: mcpToolQualityUrlWithDates(dateFilter, pinnedInterval),
                },
                { key: 'mcp-analytics-tool', name: toolName },
            ],
        ],
    }),

    listeners(({ actions }) => ({
        loadAllSections: () => {
            actions.loadSummary()
            actions.loadDescriptions()
            actions.loadDailyStats()
            actions.loadJourney()
            actions.loadExamples()
            actions.loadByHarnessRows()
            actions.loadTopModelRows()
            actions.loadTopUserRows()
        },
    })),

    // React to the shared filters' value, whatever changed it.
    subscriptions(({ actions }) => ({
        sharedQueryFilters: (_: MCPSharedQueryFilters, previous: MCPSharedQueryFilters | undefined) => {
            if (previous) {
                actions.openExample(null)
                actions.loadAllSections()
            }
        },
    })),

    // Keyed by tool, so back/forward doesn't remount; re-read the URL here.
    urlToAction(({ actions, values, cache }) => {
        const syncFromUrl = (searchParams: Record<string, any>, defaultDateFilter: DateFilter): void => {
            const dateFrom =
                typeof searchParams.date_from === 'string' ? searchParams.date_from : defaultDateFilter.dateFrom
            const dateTo = typeof searchParams.date_to === 'string' ? searchParams.date_to : null
            const dateChanged = dateFrom !== values.dateFilter.dateFrom || dateTo !== values.dateFilter.dateTo
            if (dateChanged) {
                actions.setDateFilter(dateFrom, dateTo)
            }
            const interval = parseIntervalParam(searchParams.interval)
            const intervalChanged = interval !== values.pinnedInterval
            if (intervalChanged) {
                actions.setPinnedInterval(interval)
            }
            if (dateChanged || !cache.hasLoaded) {
                actions.loadAllSections()
            } else if (intervalChanged) {
                // Only the trend series buckets by interval; every other section is a single-window
                // aggregate that a grouping change cannot move.
                actions.loadDailyStats()
            }
            cache.hasLoaded = true
        }
        return {
            [`${urls.mcpAnalyticsToolQuality()}/:toolName`]: (_, searchParams) =>
                syncFromUrl(searchParams, DEFAULT_DATE_FILTER),
            [urls.mcpAnalyticsToolQuality()]: (_, searchParams) =>
                syncFromUrl(searchParams, TOOL_QUALITY_DEFAULT_DATE_FILTER),
        }
    }),

    // Off the Tool quality routes (e.g. the dashboard drawer), load once here.
    afterMount(({ actions, values, cache }) => {
        if (cache.hasLoaded) {
            return
        }
        const { searchParams } = router.values
        const dateFrom =
            typeof searchParams.date_from === 'string'
                ? searchParams.date_from
                : TOOL_QUALITY_DEFAULT_DATE_FILTER.dateFrom
        const dateTo = typeof searchParams.date_to === 'string' ? searchParams.date_to : null
        if (dateFrom !== values.dateFilter.dateFrom || dateTo !== values.dateFilter.dateTo) {
            actions.setDateFilter(dateFrom, dateTo)
        }
        actions.loadAllSections()
        cache.hasLoaded = true
    }),
])
