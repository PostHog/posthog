import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'

import { MCPMissingCapabilitiesItem, NodeKind } from '~/queries/schema/schema-general'
import { AnyPropertyFilter } from '~/types'

import { McpFacetFilters, mcpAnalyticsFiltersLogic } from '../mcpAnalyticsFiltersLogic'
import type { DateFilter } from '../mcpAnalyticsToolQualityLogic'
import { mcpDashboardOverviewLogic } from '../mcpDashboardOverviewLogic'
import { reportProperties } from '../missingCapabilities/mcpMissingCapabilitiesLogic'

const SUGGESTED_FIXES_SHOWN = 5

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardSuggestedFixesLogicValues {
    facetFilters: McpFacetFilters // mcpAnalyticsFiltersLogic
    filterTestAccounts: boolean // mcpAnalyticsFiltersLogic
    propertyFilters: AnyPropertyFilter[] // mcpAnalyticsFiltersLogic
    dateFilter: DateFilter // mcpDashboardOverviewLogic
    openedFix: MCPMissingCapabilitiesItem | null
    queryKey: string
    suggestedFixes: MCPMissingCapabilitiesItem[]
    suggestedFixesFailed: boolean
    suggestedFixesLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardSuggestedFixesLogicActions {
    reloadAll: () => {
        value: true
    } // mcpDashboardOverviewLogic
    loadSuggestedFixes: (_: void) => void
    loadSuggestedFixesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSuggestedFixesSuccess: (
        suggestedFixes: MCPMissingCapabilitiesItem[],
        payload?: void
    ) => {
        suggestedFixes: MCPMissingCapabilitiesItem[]
        payload?: void
    }
    openFix: (fix: MCPMissingCapabilitiesItem | null) => {
        fix: MCPMissingCapabilitiesItem | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardSuggestedFixesLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        queryKey: (
            dateFilter: DateFilter,
            filterTestAccounts: boolean,
            propertyFilters: AnyPropertyFilter[],
            facetFilters: McpFacetFilters
        ) => string
    }
}

export type dashboardSuggestedFixesLogicType = MakeLogicType<
    dashboardSuggestedFixesLogicValues,
    dashboardSuggestedFixesLogicActions,
    Record<string, any>,
    dashboardSuggestedFixesLogicMeta
>

export const dashboardSuggestedFixesLogic = kea<dashboardSuggestedFixesLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'leaderboardHome', 'dashboardSuggestedFixesLogic']),
    connect(() => ({
        values: [
            mcpDashboardOverviewLogic,
            ['dateFilter'],
            mcpAnalyticsFiltersLogic,
            ['filterTestAccounts', 'propertyFilters', 'facetFilters'],
        ],
        actions: [mcpDashboardOverviewLogic, ['reloadAll']],
    })),
    actions({
        openFix: (fix: MCPMissingCapabilitiesItem | null) => ({ fix }),
    }),
    selectors({
        queryKey: [
            (s) => [s.dateFilter, s.filterTestAccounts, s.propertyFilters, s.facetFilters],
            (
                dateFilter: DateFilter,
                filterTestAccounts: boolean,
                propertyFilters: AnyPropertyFilter[],
                facetFilters: McpFacetFilters
            ): string =>
                JSON.stringify({
                    dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo },
                    filterTestAccounts,
                    properties: reportProperties(propertyFilters, facetFilters, true),
                }),
        ],
    }),
    loaders(({ values }) => ({
        suggestedFixes: [
            [] as MCPMissingCapabilitiesItem[],
            {
                loadSuggestedFixes: async (_: void, breakpoint) => {
                    const response = (await api.query({
                        kind: NodeKind.MCPMissingCapabilitiesQuery,
                        ...JSON.parse(values.queryKey),
                        limit: SUGGESTED_FIXES_SHOWN,
                        offset: 0,
                    })) as { results?: MCPMissingCapabilitiesItem[] }
                    breakpoint()
                    return response.results ?? []
                },
            },
        ],
    })),
    reducers({
        openedFix: [
            null as MCPMissingCapabilitiesItem | null,
            {
                openFix: (_, { fix }) => fix,
                loadSuggestedFixes: () => null,
            },
        ],
        suggestedFixesFailed: [
            false,
            {
                loadSuggestedFixes: () => false,
                loadSuggestedFixesFailure: () => true,
            },
        ],
    }),
    listeners(({ actions }) => ({
        // The dashboard fires reloadAll on Refresh and on every date or filter change, so this covers both.
        reloadAll: () => actions.loadSuggestedFixes(),
    })),
    afterMount(({ actions }) => {
        actions.loadSuggestedFixes()
    }),
])
