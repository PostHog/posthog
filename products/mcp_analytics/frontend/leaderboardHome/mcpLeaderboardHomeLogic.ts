import { MakeLogicType, connect, kea, path, selectors } from 'kea'

import { normalizeBucket } from 'lib/utils/timeBuckets'

import { MCPDashboardSection } from '~/queries/schema/schema-general'

import {
    mcpDashboardOverviewLogic,
    type SectionFlags,
    type SectionResults,
    sectionRows,
} from '../mcpDashboardOverviewLogic'
import type { LoadedSection } from '../mcpDashboardOverviewLogic'
import { type BucketedFacetRow } from './leaderboardShares'

export interface LeaderboardFacets {
    model: BucketedFacetRow[]
    protocolVersion: BucketedFacetRow[]
    tool: BucketedFacetRow[]
    harness: BucketedFacetRow[]
    errorType: BucketedFacetRow[]
    user: BucketedFacetRow[]
    failedFacets: FacetKey[]
}

export type FacetKey = Exclude<keyof LeaderboardFacets, 'failedFacets'>

const FACET_SECTIONS: Record<FacetKey, MCPDashboardSection> = {
    model: MCPDashboardSection.Model,
    protocolVersion: MCPDashboardSection.ProtocolVersion,
    tool: MCPDashboardSection.ToolShare,
    harness: MCPDashboardSection.Harness,
    errorType: MCPDashboardSection.ErrorTypeShare,
    user: MCPDashboardSection.User,
}

type Row = unknown[]

const toBucketedRows = (rows: Row[]): BucketedFacetRow[] =>
    rows.map((r) => ({ bucket: normalizeBucket(r[0]), label: String(r[1]), calls: Number(r[2]) }))

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface mcpLeaderboardHomeLogicValues {
    failedLoads: SectionFlags // mcpDashboardOverviewLogic
    sections: SectionResults // mcpDashboardOverviewLogic
    facets: LeaderboardFacets
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface mcpLeaderboardHomeLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        facets: (
            sections: Partial<Record<MCPDashboardSection, LoadedSection>>,
            failedLoads: Partial<Record<MCPDashboardSection, boolean>>
        ) => LeaderboardFacets
    }
}

export type mcpLeaderboardHomeLogicType = MakeLogicType<
    mcpLeaderboardHomeLogicValues,
    {},
    Record<string, any>,
    mcpLeaderboardHomeLogicMeta
>

export const mcpLeaderboardHomeLogic = kea<mcpLeaderboardHomeLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'leaderboardHome', 'mcpLeaderboardHomeLogic']),
    connect(() => ({
        values: [mcpDashboardOverviewLogic, ['sections', 'failedLoads']],
    })),
    selectors({
        facets: [
            (s) => [s.sections, s.failedLoads],
            (sections: SectionResults, failedLoads: SectionFlags): LeaderboardFacets => ({
                model: toBucketedRows(sectionRows<Row>(sections, FACET_SECTIONS.model)),
                protocolVersion: toBucketedRows(sectionRows<Row>(sections, FACET_SECTIONS.protocolVersion)),
                tool: toBucketedRows(sectionRows<Row>(sections, FACET_SECTIONS.tool)),
                harness: toBucketedRows(sectionRows<Row>(sections, FACET_SECTIONS.harness)),
                errorType: toBucketedRows(sectionRows<Row>(sections, FACET_SECTIONS.errorType)),
                user: toBucketedRows(sectionRows<Row>(sections, FACET_SECTIONS.user)),
                failedFacets: (Object.keys(FACET_SECTIONS) as FacetKey[]).filter(
                    (key) => failedLoads[FACET_SECTIONS[key]]
                ),
            }),
        ],
    }),
])
