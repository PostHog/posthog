export const mcpLeaderboardHomeLogic = kea<mcpLeaderboardHomeLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'leaderboardHome', 'mcpLeaderboardHomeLogic']),
    connect(() => ({
        values: [mcpDashboardOverviewLogic, ['sections', 'failedLoads', 'bucketKeys', 'modelRows']],
    })),
    actions({
        setScoreboardMetric: (metric: ScoreboardMetric) => ({ metric }),
    }),
    reducers({
        scoreboardMetric: [
            'calls' as ScoreboardMetric,
            {
                setScoreboardMetric: (_, { metric }) => metric,
            },
        ],
    }),
    selectors({
        facets: [
            (s) => [s.sections, s.failedLoads],
            (sections: SectionResults, failedLoads: SectionFlags): LeaderboardFacets => ({
                model: toBucketedRows(sectionRows<Row>(sections, MCPDashboardSection.Model)),
                protocolVersion: toBucketedRows(sectionRows<Row>(sections, MCPDashboardSection.ProtocolVersion)),
                tool: toWindowRows(sectionRows<Row>(sections, MCPDashboardSection.Tool)),
                errorType: toWindowRows(sectionRows<Row>(sections, MCPDashboardSection.ErrorType)),
                labUsers: sectionRows<Row>(sections, MCPDashboardSection.LabUsers).map((r) => ({
                    lab: String(r[0]),
                    users: Number(r[1]),
                })),
                namedModelUsers: Number(sectionRows<Row>(sections, MCPDashboardSection.NamedModelUsers)[0]?.[0] ?? 0),
                failedFacets: FACET_KEYS.filter((key) => failedLoads[key as MCPDashboardSection]),
            }),
        ],
        reliabilityRows: [
            (s) => [s.sections],
            (sections: SectionResults): ReliabilityRow[] =>
                toReliabilityRows(sectionRows<Row>(sections, MCPDashboardSection.Reliability)),
        ],
        reliabilityFailed: [(s) => [s.failedLoads], (failedLoads: SectionFlags): boolean => !!failedLoads.reliability],
        labShares: [(s) => [s.facets], (facets: LeaderboardFacets): LabShare[] => buildLabShares(facets.model)],
        scoreboardShares: [
            (s) => [s.scoreboardMetric, s.labShares, s.facets],
            (metric: ScoreboardMetric, callShares: LabShare[], facets: LeaderboardFacets): LabShare[] => {
                if (metric === 'calls') {
                    return callShares
                }
                // A failed denominator would otherwise show as 0% for every lab.
                const usersFailed = facets.failedFacets.some((key) => USER_SHARE_FACETS.includes(key))
                return usersFailed ? [] : buildLabUserShares(facets.labUsers, facets.namedModelUsers)
            },
        ],
        // Built from the time chart's rows, which hold every model, unlike the bar chart's capped list.
        modelRowLabelMap: [
            (s) => [s.facets],
            (facets: LeaderboardFacets): Map<string, string> => {
                const totals = new Map<string, number>()
                for (const row of facets.model) {
                    totals.set(row.label, (totals.get(row.label) ?? 0) + row.calls)
                }
                return modelRowLabelsByCalls(totals)
            },
        ],
        modelSeries: [
            (s) => [s.facets, s.bucketKeys, s.modelRowLabelMap],
            (facets: LeaderboardFacets, bucketKeys: string[], modelRowLabelMap: Map<string, string>): ShareSeries[] =>
                buildModelShareSeries(facets.model, bucketKeys, modelRowLabelMap),
        ],
        leaderboardModelRows: [
            (s) => [s.facets, s.modelRows],
            (facets: LeaderboardFacets, modelRows: ModelRow[]): ModelRow[] =>
                facets.failedFacets.includes('model') || facets.model.length === 0
                    ? modelRows
                    : modelRowsFromBuckets(facets.model),
        ],
        labSeries: [
            (s) => [s.facets, s.bucketKeys],
            (facets: LeaderboardFacets, bucketKeys: string[]): ShareSeries[] =>
                buildShareSeries(
                    facets.model,
                    bucketKeys,
                    (label) => (label === 'Unknown' ? null : modelLab(label)),
                    MODEL_SERIES_LIMIT
                ),
        ],
        pageModels: [
            (s) => [s.leaderboardModelRows, s.modelSeries, s.modelRowLabelMap],
            (modelRows: ModelRow[], modelSeries: ShareSeries[], modelRowLabelMap: Map<string, string>): string[] => [
                ...modelSeries.map((series) => series.label),
                ...summarizeModelBreakdown(modelRows, modelRowLabelMap).rankedModels.map((row) => row.model),
            ],
        ],
        protocolVersionSeries: [
            (s) => [s.facets, s.bucketKeys],
            (facets: LeaderboardFacets, bucketKeys: string[]): ShareSeries[] =>
                buildShareSeries(facets.protocolVersion, bucketKeys, (label) => label, PROTOCOL_SERIES_LIMIT),
        ],
        reliabilitySeries: [
            (s) => [s.reliabilityRows, s.bucketKeys],
            (rows: ReliabilityRow[], bucketKeys: string[]): ReliabilitySeries =>
                buildReliabilitySeries(rows, bucketKeys),
        ],
    }),
])
