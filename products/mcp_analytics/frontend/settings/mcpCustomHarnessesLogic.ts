export const mcpCustomHarnessesLogic = kea<mcpCustomHarnessesLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'settings', 'mcpCustomHarnessesLogic']),
    actions({
        startAddingHarness: true,
        startEditingHarness: (harness: MCPCustomHarnessApi) => ({ harness }),
        cancelEditingHarness: true,
        deleteCustomHarness: (id: string) => ({ id }),
        deleteCustomHarnessFinished: true,
    }),
    reducers({
        editingHarnessId: [
            null as EditingHarnessId,
            {
                startAddingHarness: () => 'new',
                startEditingHarness: (_, { harness }) => harness.id,
                cancelEditingHarness: () => null,
                submitCustomHarnessFormSuccess: () => null,
            },
        ],
        deletingHarnessId: [
            null as string | null,
            {
                deleteCustomHarness: (_, { id }) => id,
                deleteCustomHarnessFinished: () => null,
            },
        ],
    }),
    loaders({
        customHarnesses: [
            null as MCPCustomHarnessApi[] | null,
            {
                loadCustomHarnesses: async () => await mcpAnalyticsCustomHarnessesList(projectId()),
            },
        ],
    }),
    selectors({
        customHarnessIcons: [
            (s) => [s.customHarnesses],
            (customHarnesses: MCPCustomHarnessApi[] | null): Map<string, string> =>
                new Map((customHarnesses ?? []).filter((h) => h.icon).map((h) => [h.name, h.icon as string])),
        ],
    }),
    forms(({ actions, values }) => ({
        customHarnessForm: {
            defaults: EMPTY_FORM,
            errors: ({ name, match_pattern, icon }) => ({
                name: name.trim() ? undefined : 'Enter a name',
                match_pattern: match_pattern.trim() ? undefined : 'Enter the text to match',
                icon: iconError(icon.trim()),
            }),
            submit: async ({ name, match_pattern, icon }) => {
                const harness = { name: name.trim(), match_pattern, icon: icon.trim() }
                const editingId = values.editingHarnessId
                try {
                    if (editingId && editingId !== 'new') {
                        await mcpAnalyticsCustomHarnessesPartialUpdate(projectId(), editingId, harness)
                    } else {
                        await mcpAnalyticsCustomHarnessesCreate(projectId(), harness)
                    }
                } catch (error) {
                    lemonToast.error(
                        (error as { detail?: string })?.detail ||
                            'Could not save the custom harness. Check the name and text, then try again.'
                    )
                    throw error
                }
                posthog.capture(editingId === 'new' ? 'mcp custom harness created' : 'mcp custom harness updated')
                actions.loadCustomHarnesses()
            },
        },
    })),
    selectors({
        saveInProgressReason: [
            (s) => [s.isCustomHarnessFormSubmitting],
            (isSubmitting: boolean): string | null => (isSubmitting ? 'Wait for the save to finish' : null),
        ],
    }),
    listeners(({ actions }) => ({
        startAddingHarness: () => {
            actions.resetCustomHarnessForm(EMPTY_FORM)
        },
        startEditingHarness: ({ harness }) => {
            actions.resetCustomHarnessForm({
                name: harness.name,
                match_pattern: harness.match_pattern,
                icon: harness.icon ?? '',
            })
        },
        cancelEditingHarness: () => {
            actions.resetCustomHarnessForm(EMPTY_FORM)
        },
        deleteCustomHarness: async ({ id }) => {
            try {
                await mcpAnalyticsCustomHarnessesDestroy(projectId(), id)
            } catch {
                lemonToast.error('Could not delete the custom harness. Try again.')
                return
            } finally {
                actions.deleteCustomHarnessFinished()
            }
            posthog.capture('mcp custom harness deleted')
            actions.loadCustomHarnesses()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadCustomHarnesses()
    }),
])
