export const mcpCustomHarnessesLogic = kea<mcpCustomHarnessesLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'settings', 'mcpCustomHarnessesLogic']),
    actions({
        deleteCustomHarness: (id: string) => ({ id }),
        deleteCustomHarnessFinished: true,
    }),
    reducers({
        deletingHarnessId: [
            null as string | null,
            {
                deleteCustomHarness: (_, { id }) => id,
                deleteCustomHarnessFinished: () => null,
            },
        ],
    }),
    loaders({
        customHarnesses: [
            null as MCPCustomHarnessApi[] | null,
            {
                loadCustomHarnesses: async () => await mcpAnalyticsCustomHarnessesList(projectId()),
            },
        ],
    }),
    forms(({ actions }) => ({
        newCustomHarness: {
            defaults: { name: '', match_pattern: '' } as NewCustomHarness,
            errors: ({ name, match_pattern }) => ({
                name: name.trim() ? undefined : 'Enter a name',
                match_pattern: match_pattern.trim() ? undefined : 'Enter the text to match',
            }),
            submit: async ({ name, match_pattern }) => {
                try {
                    await mcpAnalyticsCustomHarnessesCreate(projectId(), { name: name.trim(), match_pattern })
                } catch (error) {
                    lemonToast.error(
                        (error as { detail?: string })?.detail ||
                            'Could not save the custom harness. Check the name and text, then try again.'
                    )
                    throw error
                }
                posthog.capture('mcp custom harness created')
                actions.resetNewCustomHarness()
                actions.loadCustomHarnesses()
            },
        },
    })),
    listeners(({ actions }) => ({
        deleteCustomHarness: async ({ id }) => {
            try {
                await mcpAnalyticsCustomHarnessesDestroy(projectId(), id)
            } catch {
                lemonToast.error('Could not delete the custom harness. Try again.')
                return
            } finally {
                actions.deleteCustomHarnessFinished()
            }
            posthog.capture('mcp custom harness deleted')
            actions.loadCustomHarnesses()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadCustomHarnesses()
    }),
])
