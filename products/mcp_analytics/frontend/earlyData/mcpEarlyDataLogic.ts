export const mcpEarlyDataLogic = kea<mcpEarlyDataLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'earlyData', 'mcpEarlyDataLogic']),
    connect(() => ({
        values: [
            mcpAnalyticsOnboardingLogic,
            ['signals'],
            teamLogic,
            ['currentProjectId'],
            mcpAnalyticsNotificationsLogic,
            ['notifications'],
        ],
        actions: [
            // Refresh the lifetime signal with the overview so first-call copy can
            // advance even after the onboarding signal poll stops.
            mcpAnalyticsOnboardingLogic,
            ['loadSignals'],
            mcpAnalyticsNotificationsLogic,
            ['loadNotifications', 'loadNotificationsSuccess'],
            dataNodeCollectionLogic({ key: MCP_ACTIVITY_DATA_COLLECTION_ID }),
            ['reloadAll as reloadActivityQuery'],
        ],
    })),
    actions({
        refreshAll: true,
        setActivityQuery: (query: DataTableNode) => ({ query }),
        showFailedCallsOnly: true,
    }),
    reducers({
        activityQuery: [DEFAULT_MCP_ACTIVITY_QUERY, { setActivityQuery: (_, { query }) => query }],
        // The list defaults to empty before its first load, which would read as "no alert set up".
        notificationsResolved: [false, { loadNotificationsSuccess: () => true }],
    }),
    loaders(({ values }) => ({
        overview: {
            __default: null as MCPActivityOverviewApi | null,
            loadOverview: async (_: void, breakpoint): Promise<MCPActivityOverviewApi | null> => {
                if (!values.currentProjectId) {
                    return null
                }
                const response = await mcpAnalyticsSessionsActivityOverview(String(values.currentProjectId))
                breakpoint()
                return response
            },
        },
        harnessRows: [
            [] as HarnessRow[],
            {
                loadHarnessRows: async (_: void, breakpoint): Promise<HarnessRow[]> => {
                    const response = (await api.query({
                        kind: NodeKind.MCPHarnessBreakdownQuery,
                        ...ACTIVITY_FILTERS,
                    })) as { results?: MCPHarnessBreakdownItem[] }
                    breakpoint()
                    return (response?.results ?? []).map((r) => ({
                        category: r.harness,
                        total_calls: r.total_calls,
                        errors: r.errors,
                        error_rate_pct: r.error_rate_pct,
                        sessions: r.sessions,
                    }))
                },
            },
        ],
        modelRows: [
            [] as ModelRow[],
            {
                loadModelRows: async (_: void, breakpoint): Promise<ModelRow[]> => {
                    const response = (await api.query({
                        kind: NodeKind.MCPModelBreakdownQuery,
                        ...ACTIVITY_FILTERS,
                    })) as { results?: MCPModelBreakdownItem[] }
                    breakpoint()
                    return response?.results ?? []
                },
            },
        ],
    })),
    selectors({
        stats: [
            (s) => [s.overview],
            (overview: MCPActivityOverviewApi | null): EarlyStats =>
                overview
                    ? {
                          totalCalls: overview.stats.total_calls,
                          distinctTools: overview.stats.distinct_tools,
                          distinctSessions: overview.stats.distinct_sessions,
                          distinctClients: overview.stats.distinct_clients,
                          callsWithIntent: overview.stats.calls_with_intent,
                          errorCalls: overview.stats.error_calls,
                          missingCapabilityReports: overview.stats.missing_capability_reports,
                      }
                    : EMPTY_STATS,
        ],
        topTools: [
            (s) => [s.overview],
            (overview: MCPActivityOverviewApi | null): EarlyToolRow[] =>
                (overview?.top_tools ?? []).map((row) => ({ tool: row.tool, calls: row.calls, errors: row.errors })),
        ],
        summary: [
            (s) => [s.signals, s.stats, s.topTools],
            (signals: MCPOnboardingSignals | null, stats: EarlyStats, topTools: EarlyToolRow[]): ActivitySummary =>
                buildActivitySummary({
                    lifetimeCalls: signals?.toolCallsTotal ?? null,
                    totalCalls: stats.totalCalls,
                    distinctClients: stats.distinctClients,
                    errorCalls: stats.errorCalls,
                    topTool: stats.totalCalls > 10 ? (topTools[0]?.tool ?? null) : null,
                }),
        ],
        // A paused alert notifies nobody, so only enabled ones count as "set up".
        hasFailureNotification: [
            (s) => [s.notificationsResolved, s.notifications],
            (resolved: boolean, notifications: HogFunctionType[]): boolean | null =>
                resolved ? notifications.some((notification) => notification.enabled) : null,
        ],
        nextSteps: [
            (s) => [s.stats, s.hasFailureNotification],
            (stats: EarlyStats, hasFailureNotification: boolean | null): NextStep[] =>
                buildNextSteps(stats, hasFailureNotification),
        ],
        hasModelData: [
            (s) => [s.modelRows],
            (modelRows: ModelRow[]): boolean => modelRows.some((row) => row.total_calls > 0),
        ],
    }),
    listeners(({ actions, values }) => ({
        refreshAll: () => {
            actions.loadSignals()
            actions.loadOverview()
            actions.loadNotifications()
            actions.loadHarnessRows()
            actions.loadModelRows()
            actions.reloadActivityQuery()
        },
        showFailedCallsOnly: () => {
            actions.setActivityQuery(withFailedCallsOnly(values.activityQuery))
        },
    })),
    afterMount(({ actions, cache }) => {
        actions.loadOverview()
        actions.loadNotifications()
        actions.loadHarnessRows()
        actions.loadModelRows()
        cache.disposables.add(() => {
            const id = window.setInterval(() => actions.refreshAll(), REFRESH_INTERVAL_MS)
            return () => clearInterval(id)
        }, 'refresh')
    }),
])
