const DEFAULT_DATE_FILTER: DateFilter = { dateFrom: '-7d', dateTo: null }

/**
 * People first: a customer's own server never stamps `$mcp_scope_preset`, so this is a no-op for
 * them, while on PostHog's hosted server it keeps automated runs out of the human numbers.
 */
const DEFAULT_CALLER_KIND: MCPCallerKind = 'people'

// Fetch more groups than the card shows: the missing-tools count reads every group whose
// message is an unknown-tool rejection, and those are rarely in the top five.
const FAILURE_GROUP_FETCH_LIMIT = 50
const FAILURE_GROUP_DISPLAY_LIMIT = 5

const MISSING_REPORT_LIMIT = 5

/** Failure groups whose message carries this are the server rejecting a tool it does not have. */
const UNKNOWN_TOOL_MARKER = 'unknown_tool'

function isCallerKind(value: unknown): value is MCPCallerKind {
    return value === 'people' || value === 'automations' || value === 'all'
}

function rankHarnessRows(rows: MCPHarnessBreakdownItem[]): MCPHarnessBreakdownItem[] {
    return [...rows].sort(
        (a, b) =>
            Number(isUnresolvedHarness(a.harness)) - Number(isUnresolvedHarness(b.harness)) ||
            b.total_calls - a.total_calls
    )
}

function rankModelRows(rows: MCPModelBreakdownItem[]): MCPModelBreakdownItem[] {
    return [...rows].sort(
        (a, b) => Number(a.model === 'Unknown') - Number(b.model === 'Unknown') || b.total_calls - a.total_calls
    )
}

