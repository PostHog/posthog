export const mcpOverviewLogic = kea<mcpOverviewLogicType>([
    path(['products', 'mcp_analytics', 'frontend', 'overview', 'mcpOverviewLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentProjectId']],
    })),
    actions({
        // One action for a URL hydration, so a deep link with several params reloads once.
        hydrateFilters: (filters: {
            dateFilter: DateFilter
            filterTestAccountsOverride: boolean | null
            propertyFilters: AnyPropertyFilter[]
            callerKind: MCPCallerKind
        }) => ({ filters }),
        setDateFilter: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setFilterTestAccounts: (filterTestAccounts: boolean | null) => ({ filterTestAccounts }),
        setPropertyFilters: (properties: AnyPropertyFilter[]) => ({ properties }),
        setCallerKind: (callerKind: MCPCallerKind) => ({ callerKind }),
        setAskInput: (askInput: string) => ({ askInput }),
        askPostHogAI: (prompt: string, source: string) => ({ prompt, source }),
        reloadAll: true,
    }),
    reducers({
        dateFilter: [
            DEFAULT_DATE_FILTER,
            {
                setDateFilter: (_, { dateFrom, dateTo }): DateFilter => ({ dateFrom, dateTo }),
                hydrateFilters: (_, { filters }): DateFilter => filters.dateFilter,
            },
        ],
        // null until the user toggles — the effective value falls back to the team's
        // test_account_filters_default_checked setting (see the filterTestAccounts selector).
        filterTestAccountsOverride: [
            null as boolean | null,
            {
                setFilterTestAccounts: (_, { filterTestAccounts }): boolean | null => filterTestAccounts,
                hydrateFilters: (_, { filters }): boolean | null => filters.filterTestAccountsOverride,
            },
        ],
        propertyFilters: [
            [] as AnyPropertyFilter[],
            {
                setPropertyFilters: (_, { properties }): AnyPropertyFilter[] => properties,
                hydrateFilters: (_, { filters }): AnyPropertyFilter[] => filters.propertyFilters,
            },
        ],
        callerKind: [
            DEFAULT_CALLER_KIND as MCPCallerKind,
            {
                setCallerKind: (_, { callerKind }): MCPCallerKind => callerKind,
                hydrateFilters: (_, { filters }): MCPCallerKind => filters.callerKind,
            },
        ],
        askInput: [
            '',
            {
                setAskInput: (_, { askInput }): string => askInput,
                askPostHogAI: (): string => '',
            },
        ],
    }),
    loaders(({ values }) => ({
        summary: [
            null as MCPOverviewSummary | null,
            {
                loadSummary: async (_: void, breakpoint): Promise<MCPOverviewSummary | null> => {
                    const { dateRange, properties, filterTestAccounts } = values.queryFilters
                    const response = (await api.query({
                        kind: NodeKind.MCPOverviewSummaryQuery,
                        dateRange,
                        properties,
                        filterTestAccounts,
                        callerKind: values.callerKind,
                    })) as { results?: MCPOverviewSummary[] }
                    breakpoint()
                    return response?.results?.[0] ?? null
                },
            },
        ],
        failureGroups: [
            [] as MCPFailureGroup[],
            {
                loadFailureGroups: async (_: void, breakpoint): Promise<MCPFailureGroup[]> => {
                    const { dateRange, properties, filterTestAccounts } = values.queryFilters
                    const response = (await api.query({
                        kind: NodeKind.MCPFailureGroupsQuery,
                        dateRange,
                        properties,
                        filterTestAccounts,
                        callerKind: values.callerKind,
                        limit: FAILURE_GROUP_FETCH_LIMIT,
                    })) as { results?: MCPFailureGroup[] }
                    breakpoint()
                    return response?.results ?? []
                },
            },
        ],
        harnessRows: [
            [] as MCPHarnessBreakdownItem[],
            {
                loadHarnessRows: async (_: void, breakpoint): Promise<MCPHarnessBreakdownItem[]> => {
                    const { dateRange, properties, filterTestAccounts } = values.queryFilters
                    const response = (await api.query({
                        kind: NodeKind.MCPHarnessBreakdownQuery,
                        dateRange,
                        properties,
                        filterTestAccounts,
                        callerKind: values.callerKind,
                    })) as { results?: MCPHarnessBreakdownItem[] }
                    breakpoint()
                    return response?.results ?? []
                },
            },
        ],
        modelRows: [
            [] as MCPModelBreakdownItem[],
            {
                loadModelRows: async (_: void, breakpoint): Promise<MCPModelBreakdownItem[]> => {
                    const { dateRange, properties, filterTestAccounts } = values.queryFilters
                    const response = (await api.query({
                        kind: NodeKind.MCPModelBreakdownQuery,
                        dateRange,
                        properties,
                        filterTestAccounts,
                        callerKind: values.callerKind,
                    })) as { results?: MCPModelBreakdownItem[] }
                    breakpoint()
                    return response?.results ?? []
                },
            },
        ],
        missingReports: [
            [] as MCPMissingCapabilitiesItem[],
            {
                loadMissingReports: async (_: void, breakpoint): Promise<MCPMissingCapabilitiesItem[]> => {
                    const { dateRange } = values.queryFilters
                    const response = (await api.query({
                        kind: NodeKind.MCPMissingCapabilitiesQuery,
                        dateRange,
                        limit: MISSING_REPORT_LIMIT,
                    })) as { results?: MCPMissingCapabilitiesItem[] }
                    breakpoint()
                    return response?.results ?? []
                },
            },
        ],
        intentDigest: [
            null as IntentDigest | null,
            {
                loadIntentDigest: async (_: void, breakpoint): Promise<IntentDigest | null> => {
                    if (!values.currentProjectId) {
                        return null
                    }
                    try {
                        // Same window as every other card, so the themes describe the calls on screen.
                        const response = await mcpAnalyticsSessionsIntentDigest(String(values.currentProjectId), {
                            caller_kind: values.callerKind,
                            date_from: values.dateFilter.dateFrom,
                            date_to: values.dateFilter.dateTo,
                        })
                        breakpoint()
                        return {
                            digest: response.digest,
                            intentCount: response.intent_count,
                            themes: response.themes ?? [],
                        }
                    } catch (error: unknown) {
                        // A newer load superseded this one; let kea-loaders skip the stale success
                        // rather than reporting it as a failed digest.
                        if (isBreakpoint(error as Error)) {
                            throw error
                        }
                        // LLM unconfigured (503) or transient failure: the card says so instead
                        // of leaving the reader with an empty panel.
                        return null
                    }
                },
            },
        ],
    })),
    selectors({
        // Effective toggle state: the user's explicit override, else the team's default.
        filterTestAccounts: [
            (s) => [s.filterTestAccountsOverride, s.currentTeam],
            (override: boolean | null, currentTeam: TeamType | null): boolean =>
                override ?? !!currentTeam?.test_account_filters_default_checked,
        ],
        queryFilters: [
            (s) => [s.dateFilter, s.filterTestAccounts, s.propertyFilters],
            (
                dateFilter: DateFilter,
                filterTestAccounts: boolean,
                propertyFilters: AnyPropertyFilter[]
            ): HogQLFilters => ({
                dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo },
                filterTestAccounts,
                // Drop incomplete picker rows and any malformed URL-hydrated entries before they fan out to every card.
                properties: propertyFilters.filter(isValidPropertyFilter),
            }),
        ],
        rangeLabel: [
            (s) => [s.dateFilter],
            (dateFilter: DateFilter): string =>
                dateFilterToText(dateFilter.dateFrom, dateFilter.dateTo, 'the selected range') ?? 'the selected range',
        ],
        clientRows: [
            (s) => [s.harnessRows],
            (harnessRows: MCPHarnessBreakdownItem[]): MCPHarnessBreakdownItem[] => rankHarnessRows(harnessRows),
        ],
        modelRowsRanked: [
            (s) => [s.modelRows],
            (modelRows: MCPModelBreakdownItem[]): MCPModelBreakdownItem[] => rankModelRows(modelRows),
        ],
        headline: [
            (s) => [s.summary, s.clientRows],
            (summary: MCPOverviewSummary | null, clientRows: MCPHarnessBreakdownItem[]): string =>
                buildHeadline(summary, clientRows),
        ],
        suggestions: [
            (s) => [s.summary, s.clientRows],
            (summary: MCPOverviewSummary | null, clientRows: MCPHarnessBreakdownItem[]): OverviewSuggestion[] =>
                buildSuggestions(summary, clientRows),
        ],
        coverageItems: [
            (s) => [s.summary, s.harnessRows, s.modelRows, s.missingReports],
            (
                summary: MCPOverviewSummary | null,
                harnessRows: MCPHarnessBreakdownItem[],
                modelRows: MCPModelBreakdownItem[],
                missingReports: MCPMissingCapabilitiesItem[]
            ): CoverageItem[] =>
                buildCoverageItems({ summary, harnessRows, modelRows, hasMissingReports: missingReports.length > 0 }),
        ],
        topFailureGroups: [
            (s) => [s.failureGroups],
            (failureGroups: MCPFailureGroup[]): MCPFailureGroup[] =>
                failureGroups.slice(0, FAILURE_GROUP_DISPLAY_LIMIT),
        ],
        // The server records that it rejected an unknown tool, not the name that was asked for,
        // so reach is all this section can report. Groups are distinct by message, so a session
        // that hit two of them counts twice; the number reads as an upper bound.
        unknownToolSessions: [
            (s) => [s.failureGroups],
            (failureGroups: MCPFailureGroup[]): number =>
                failureGroups
                    .filter((group) => group.message.toLowerCase().includes(UNKNOWN_TOOL_MARKER))
                    .reduce((sum, group) => sum + group.sessions, 0),
        ],
        reloading: [
            (s) => [s.summaryLoading, s.failureGroupsLoading, s.harnessRowsLoading, s.modelRowsLoading],
            (
                summaryLoading: boolean,
                failureGroupsLoading: boolean,
                harnessRowsLoading: boolean,
                modelRowsLoading: boolean
            ): boolean => summaryLoading || failureGroupsLoading || harnessRowsLoading || modelRowsLoading,
        ],
    }),
    listeners(({ actions, values }) => ({
        setDateFilter: () => actions.reloadAll(),
        setFilterTestAccounts: () => actions.reloadAll(),
        setPropertyFilters: () => actions.reloadAll(),
        setCallerKind: () => actions.reloadAll(),
        hydrateFilters: () => actions.reloadAll(),
        reloadAll: () => {
            actions.loadSummary()
            actions.loadFailureGroups()
            actions.loadHarnessRows()
            actions.loadModelRows()
            actions.loadMissingReports()
            actions.loadIntentDigest()
        },
        askPostHogAI: ({ prompt, source }) => {
            posthog.captureRaw('mcp analytics overview ask ai clicked', {
                source,
                caller_kind: values.callerKind,
            })
            // Prefill, don't auto-submit: these prompts embed tool names, error messages and
            // intents from `$mcp_tool_call` events, which anyone with the project token can set.
            // Auto-running one would let seeded text reach PostHog AI as an instruction.
            sidePanelStateLogic.findMounted()?.actions.openSidePanel(SidePanelTab.Max, prompt)
        },
    })),
    actionToUrl(({ values }) => {
        const syncUrl = (): [string, Record<string, any>, Record<string, any>, { replace: boolean }] => {
            const { currentLocation } = router.values
            const searchParams = { ...currentLocation.searchParams }
            if (values.dateFilter.dateFrom) {
                searchParams.date_from = values.dateFilter.dateFrom
            } else {
                delete searchParams.date_from
            }
            if (values.dateFilter.dateTo) {
                searchParams.date_to = values.dateFilter.dateTo
            } else {
                delete searchParams.date_to
            }
            // Absent param = follow the team default; an explicit override (incl. false) persists.
            if (values.filterTestAccountsOverride === null) {
                delete searchParams.filter_test_accounts
            } else {
                searchParams.filter_test_accounts = values.filterTestAccountsOverride
            }
            if (values.propertyFilters.length > 0) {
                searchParams.properties = values.propertyFilters
            } else {
                delete searchParams.properties
            }
            if (values.callerKind === DEFAULT_CALLER_KIND) {
                delete searchParams.caller_kind
            } else {
                searchParams.caller_kind = values.callerKind
            }
            return [currentLocation.pathname, searchParams, currentLocation.hashParams, { replace: true }]
        }
        return {
            setDateFilter: syncUrl,
            setFilterTestAccounts: syncUrl,
            setPropertyFilters: syncUrl,
            setCallerKind: syncUrl,
        }
    }),
    urlToAction(({ actions, values, cache }) => ({
        [urls.mcpAnalyticsOverview()]: (_, searchParams) => {
            const dateFrom =
                typeof searchParams.date_from === 'string' ? searchParams.date_from : DEFAULT_DATE_FILTER.dateFrom
            const dateTo = typeof searchParams.date_to === 'string' ? searchParams.date_to : null
            // Absent param leaves the override null (effective value follows the team default).
            const rawFilter = searchParams.filter_test_accounts
            const filterOverride = rawFilter === undefined ? null : rawFilter === true || rawFilter === 'true'
            const properties = Array.isArray(searchParams.properties) ? searchParams.properties : []
            const callerKind = isCallerKind(searchParams.caller_kind) ? searchParams.caller_kind : DEFAULT_CALLER_KIND
            const dateChanged = dateFrom !== values.dateFilter.dateFrom || dateTo !== values.dateFilter.dateTo
            const filterChanged = filterOverride !== values.filterTestAccountsOverride
            const propertiesChanged = JSON.stringify(properties) !== JSON.stringify(values.propertyFilters)
            const callerKindChanged = callerKind !== values.callerKind
            if (dateChanged || filterChanged || propertiesChanged || callerKindChanged) {
                actions.hydrateFilters({
                    dateFilter: { dateFrom, dateTo },
                    filterTestAccountsOverride: filterOverride,
                    propertyFilters: properties,
                    callerKind,
                })
            } else if (!cache.hasLoaded) {
                // URL already matches state (e.g. default filters) and afterMount deferred — load once.
                actions.reloadAll()
            }
            cache.hasLoaded = true
        },
    })),
    afterMount(({ actions, cache }) => {
        // urlToAction owns the initial load whenever the URL carries filter params; this is the
        // fallback for a param-less mount (and off-route mounts in tests, where urlToAction never
        // fires). The cache.hasLoaded guard keeps a deep-linked load from firing twice.
        const { searchParams } = router.values
        const hasUrlFilters =
            typeof searchParams.date_from === 'string' ||
            typeof searchParams.date_to === 'string' ||
            typeof searchParams.filter_test_accounts !== 'undefined' ||
            typeof searchParams.caller_kind === 'string' ||
            Array.isArray(searchParams.properties)
        if (!hasUrlFilters && !cache.hasLoaded) {
            cache.hasLoaded = true
            actions.reloadAll()
        }
    }),
])
