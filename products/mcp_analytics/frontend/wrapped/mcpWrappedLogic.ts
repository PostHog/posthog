export const mcpWrappedLogic = kea<mcpWrappedLogicType>([
    // pinned: the path sets the localStorage key of seenWrapKeys
    path(['products', 'mcp_analytics', 'frontend', 'wrapped', 'mcpWrappedLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        showTeaser: true,
        openStory: (source: WrappedSource) => ({ source }),
        closeWrapped: true,
        markSeen: (wrapKey: string) => ({ wrapKey }),
        showCard: (index: number) => ({ index }),
        nextCard: true,
        previousCard: true,
        setPaused: (paused: boolean) => ({ paused }),
        setPageHidden: (hidden: boolean) => ({ hidden }),
        shareCaptured: (method: 'share' | 'copy' | 'download') => ({ method }),
    }),
    loaders(({ values }) => ({
        wrapped: [
            null as MCPWrappedApi | null,
            {
                loadWrapped: async () => {
                    const response = await mcpAnalyticsWrappedRetrieve(String(values.currentProjectId))
                    return response.wrapped
                },
            },
        ],
    })),
    reducers({
        view: [
            'closed' as WrappedView,
            {
                showTeaser: () => 'teaser',
                openStory: () => 'story',
                closeWrapped: () => 'closed',
            },
        ],
        cardIndex: [
            0,
            {
                openStory: () => 0,
                showCard: (_, { index }) => index,
            },
        ],
        paused: [
            false,
            {
                openStory: () => false,
                setPaused: (_, { paused }) => paused,
            },
        ],
        pageHidden: [
            false,
            {
                setPageHidden: (_, { hidden }) => hidden,
            },
        ],
        seenWrapKeys: [
            [] as string[],
            { persist: true },
            {
                markSeen: (state, { wrapKey }) => (state.includes(wrapKey) ? state : [...state, wrapKey]),
            },
        ],
    }),
    selectors({
        cardKeys: [
            (s) => [s.wrapped],
            (wrapped: MCPWrappedApi | null): WrappedCardKey[] => (wrapped ? storyCardKeys(wrapped.cards) : []),
        ],
        currentCardKey: [
            (s) => [s.cardKeys, s.cardIndex],
            (cardKeys: WrappedCardKey[], cardIndex: number): WrappedCardKey | null => cardKeys[cardIndex] ?? null,
        ],
        // One wrap per project and computation, so a rerun of the job shows the pop-up again.
        wrapKey: [
            (s) => [s.currentProjectId, s.wrapped],
            (projectId: number | null, wrapped: MCPWrappedApi | null): string | null =>
                wrapped ? `${projectId}:${wrapped.generated_at}` : null,
        ],
        hasUnseenWrap: [
            (s) => [s.wrapKey, s.seenWrapKeys],
            (wrapKey: string | null, seenWrapKeys: string[]): boolean => !!wrapKey && !seenWrapKeys.includes(wrapKey),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        // The card timer keeps the time left on the current card, so a pause or a hidden tab resumes where the
        // progress bar stopped. setPageHidden stops it while the tab is hidden, so the disposable doesn't pause too.
        const stopTimer = (): void => cache.disposables.dispose('cardTimer')
        const startTimer = (): void => {
            const isLast = values.cardIndex >= values.cardKeys.length - 1
            if (values.view !== 'story' || values.paused || values.pageHidden || isLast) {
                return
            }
            cache.disposables.add(
                () => {
                    const startedAt = Date.now()
                    const timer = setTimeout(() => actions.nextCard(), cache.remainingMs)
                    return () => {
                        clearTimeout(timer)
                        cache.remainingMs = Math.max(0, cache.remainingMs - (Date.now() - startedAt))
                    }
                },
                'cardTimer',
                { pauseOnPageHidden: false }
            )
        }
        const restartCard = (): void => {
            stopTimer()
            cache.remainingMs = CARD_DURATION_MS
            startTimer()
        }
        const trackCard = (): void => {
            // pinned: analytics event and property names, renaming breaks dashboards
            posthog.capture('mcp wrapped card viewed', {
                card: values.currentCardKey,
                index: values.cardIndex,
                cards: values.cardKeys.length,
            })
            if (values.cardIndex === values.cardKeys.length - 1) {
                posthog.capture('mcp wrapped completed', { cards: values.cardKeys.length })
            }
        }
        return {
            loadWrappedSuccess: () => {
                if (values.hasUnseenWrap && values.view === 'closed') {
                    actions.showTeaser()
                    posthog.capture('mcp wrapped shown', { year: values.wrapped?.year })
                }
            },
            openStory: ({ source }) => {
                posthog.capture('mcp wrapped opened', { source, year: values.wrapped?.year })
                trackCard()
                restartCard()
            },
            showCard: () => {
                trackCard()
                restartCard()
            },
            nextCard: () => {
                if (values.cardIndex < values.cardKeys.length - 1) {
                    actions.showCard(values.cardIndex + 1)
                }
            },
            previousCard: () => {
                if (values.cardIndex > 0) {
                    actions.showCard(values.cardIndex - 1)
                }
            },
            setPaused: ({ paused }) => (paused ? stopTimer() : startTimer()),
            setPageHidden: ({ hidden }) => (hidden ? stopTimer() : startTimer()),
            closeWrapped: () => {
                stopTimer()
                if (values.wrapKey) {
                    actions.markSeen(values.wrapKey)
                }
                posthog.capture('mcp wrapped closed', { card: values.currentCardKey, index: values.cardIndex })
            },
            shareCaptured: ({ method }) => {
                posthog.capture('mcp wrapped shared', { method })
            },
        }
    }),
    afterMount(({ actions, values, cache }) => {
        if (values.featureFlags[FEATURE_FLAGS.MCP_ANALYTICS_WRAPPED]) {
            actions.loadWrapped()
        }
        // The progress bar pauses with the timer while the tab is hidden, so neither runs ahead unseen.
        cache.disposables.add(
            () => {
                const onVisibilityChange = (): void => actions.setPageHidden(document.hidden)
                document.addEventListener('visibilitychange', onVisibilityChange)
                return () => document.removeEventListener('visibilitychange', onVisibilityChange)
            },
            'visibility',
            { pauseOnPageHidden: false }
        )
    }),
])
