import {
    MakeLogicType,
    actions,
    afterMount,
    beforeUnmount,
    connect,
    kea,
    listeners,
    path,
    reducers,
    selectors,
} from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { teamLogic } from 'scenes/teamLogic'

import type { FeatureFlagsSet } from '../../../../frontend/src/lib/logic/featureFlagLogic'
import { mcpAnalyticsWrappedRetrieve } from '../generated/api'
import type { MCPWrappedApi } from '../generated/api.schemas'
import { WrappedCardKey, storyCardKeys } from './storyCards'

export const CARD_DURATION_MS = 7000

export type WrappedSource = 'pop_up' | 'header_button'
export type WrappedView = 'closed' | 'teaser' | 'story'

