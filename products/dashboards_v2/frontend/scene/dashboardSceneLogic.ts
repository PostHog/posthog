export const dashboardSceneLogic = kea<dashboardSceneLogicType>([
    props({} as DashboardSceneLogicProps),
    key((props) => props.uid ?? 'fixture'),
    path((key) => ['products', 'dashboardsV2', 'scene', 'dashboardSceneLogic', key]),
    actions({
        /** The one entry point for edits to the layout. Drags and menus call it, so the permission check lives here only. */
        applyDashboardEdit: (edit: DashboardEdit, view?: View) => ({ edit, view }),
        commitDashboard: (dashboard: Dashboard) => ({ dashboard }),
        undo: true,
        redo: true,
        stepHistory: (step: 'back' | 'forward') => ({ step }),
        setActiveTab: (tabId: string) => ({ tabId }),
        scheduleSave: true,
        saveBoard: true,
        saveStarted: true,
        boardSaved: (board: Board, dashboard: Dashboard) => ({ board, dashboard }),
        saveFailed: true,
        boardConflicted: (conflict: BoardConflict) => ({ conflict }),
        keepTheirVersion: true,
        keepMyVersion: true,
        /** Starts over from a board as stored, with no undo steps. */
        resetToBoard: (board: Board) => ({ board, dashboard: dashboardOf(board) }),
        /** Keeps the dashboard on screen, but saves it over `board`, the version someone else saved. */
        rebaseOnBoard: (board: Board) => ({ board, dashboard: dashboardOf(board) }),
    }),
    loaders(({ props }) => ({
        board: [
            null as Board | null,
            {
                loadBoard: async () => (props.uid ? await getDashboardBoard(props.uid) : null),
            },
        ],
    })),
    reducers(({ props }) => ({
        board: {
            boardSaved: (_, { board }) => board,
            resetToBoard: (_, { board }) => board,
            rebaseOnBoard: (_, { board }) => board,
        },
        history: [
            // TODO(2026-11-23): Delete the kitchen sink fixture once the board list can open saved boards.
            // Without a board in the URL, the scene shows the fixture and saves nothing.
            (props.uid ? null : startHistory(settleDashboard(kitchenSinkDashboard, sizeOf))) as DashboardHistory | null,
            {
                resetToBoard: (_, { dashboard }) => startHistory(dashboard),
                commitDashboard: (state, { dashboard }) => state && recordEdit(state, dashboard),
                stepHistory: (state, { step }) => state && (step === 'back' ? undoEdit(state) : redoEdit(state)),
            },
        ],
        /** The dashboard as the board last stored it from this person, so an edit since then is unsaved. */
        savedDashboard: [
            null as Dashboard | null,
            {
                boardSaved: (_, { dashboard }) => dashboard,
                resetToBoard: (_, { dashboard }) => dashboard,
                rebaseOnBoard: (_, { dashboard }) => dashboard,
            },
        ],
        unavailable: [
            null as UnavailableReason | null,
            {
                loadBoard: () => null,
                loadBoardFailure: (_, { errorObject }) => unavailableReason(errorObject),
            },
        ],
        saveStatus: [
            'idle' as 'idle' | 'saving' | 'failed',
            {
                saveStarted: () => 'saving',
                boardSaved: () => 'idle',
                saveFailed: () => 'failed',
                boardConflicted: () => 'idle',
            },
        ],
        conflict: [
            null as BoardConflict | null,
            {
                boardConflicted: (_, { conflict }) => conflict,
                resetToBoard: () => null,
                rebaseOnBoard: () => null,
            },
        ],
        activeTabId: [null as string | null, { setActiveTab: (_, { tabId }) => tabId }],
    })),
    selectors({
        dashboard: [
            (s) => [s.history],
            (history: DashboardHistory | null): Dashboard | null => history?.present ?? null,
        ],
        canUndo: [(s) => [s.history], (history: DashboardHistory | null): boolean => !!history?.past.length],
        canRedo: [(s) => [s.history], (history: DashboardHistory | null): boolean => !!history?.future.length],
        saveState: [
            (s) => [s.board, s.dashboard, s.savedDashboard, s.saveStatus, s.conflict],
            (
                board: Board | null,
                dashboard: Dashboard | null,
                savedDashboard: Dashboard | null,
                saveStatus: 'idle' | 'saving' | 'failed',
                conflict: BoardConflict | null
            ): SaveState | null => {
                if (!board) {
                    return null
                }
                if (conflict) {
                    return 'conflict'
                }
                if (saveStatus !== 'idle') {
                    return saveStatus
                }
                return dashboard === savedDashboard ? 'saved' : 'unsaved'
            },
        ],
        conflictChanges: [
            (s) => [s.conflict, s.dashboard],
            (
                conflict: BoardConflict | null,
                dashboard: Dashboard | null
            ): { theirs: string[]; yours: string[] } | null =>
                conflict && dashboard
                    ? {
                          theirs: describeChanges(conflict.base, dashboardOf(conflict.theirs)),
                          yours: describeChanges(conflict.base, dashboard),
                      }
                    : null,
        ],
        disabledReasonFor: [
            (s) => [s.dashboard, s.board, s.conflict],
            // Every edit needs Editor, as on v1 dashboards. When the dashboard has no `user_access_level`, this
            // falls back to the project-wide dashboard level.
            (
                dashboard: Dashboard | null,
                board: Board | null,
                conflict: BoardConflict | null
            ): ((action: DashboardAction) => string | null) =>
                () => {
                    if (board && board.managed_by !== 'native') {
                        return 'This dashboard is managed outside PostHog, so it can only be changed there'
                    }
                    if (conflict) {
                        return 'Someone else saved this dashboard. Choose which version to keep first'
                    }
                    return getAccessControlDisabledReason(
                        AccessControlResourceType.Dashboard,
                        AccessControlLevel.Editor,
                        dashboard?.user_access_level,
                        false
                    )
                },
        ],
        activeTab: [
            (s) => [s.dashboard, s.activeTabId],
            (dashboard: Dashboard | null, activeTabId: string | null): GridTab | null =>
                dashboard && activeGridTab(dashboard, activeTabId),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        applyDashboardEdit: ({ edit, view }) => {
            const { dashboard, history, activeTab } = values
            if (!dashboard || !history || values.disabledReasonFor(edit.edit)) {
                return
            }
            const next = applyEdit(dashboard, edit, sizeOf, view)
            if (recordEdit(history, next) === history) {
                return
            }
            // With no tab in the URL the first tab shows, so a reorder would switch tabs unless the shown one is pinned.
            if (edit.edit === 'moveTab' && values.activeTabId === null && activeTab) {
                actions.setActiveTab(activeTab.id)
            }
            actions.commitDashboard(next)
            if (edit.edit === 'addTab') {
                actions.setActiveTab(next.tabs[next.tabs.length - 1].id)
            }
        },
        undo: () => {
            if (!values.disabledReasonFor('undo')) {
                actions.stepHistory('back')
            }
        },
        redo: () => {
            if (!values.disabledReasonFor('redo')) {
                actions.stepHistory('forward')
            }
        },
        loadBoardSuccess: ({ board }) => {
            if (board) {
                actions.resetToBoard(board)
            }
        },
        commitDashboard: () => actions.scheduleSave(),
        stepHistory: () => actions.scheduleSave(),
        scheduleSave: async (_, breakpoint) => {
            await breakpoint(SAVE_DELAY_MS)
            actions.saveBoard()
        },
        saveBoard: async () => {
            const { board, dashboard, saveState } = values
            if (!props.uid || !board || !dashboard || (saveState !== 'unsaved' && saveState !== 'failed')) {
                return
            }
            actions.saveStarted()
            try {
                actions.boardSaved(await updateBoard(props.uid, saveDashboard(dashboard), board.version), dashboard)
            } catch (error) {
                if (!(error instanceof ApiError) || error.status !== 409) {
                    actions.saveFailed()
                    return
                }
                try {
                    const theirs = await getDashboardBoard(props.uid)
                    actions.boardConflicted({ theirs, base: values.savedDashboard ?? dashboard })
                } catch {
                    actions.saveFailed()
                }
                return
            }
            // One save runs at a time, so an edit made while it ran is saved now, against the version it returned.
            if (values.dashboard !== dashboard) {
                actions.saveBoard()
            }
        },
        keepTheirVersion: () => {
            const { conflict } = values
            if (conflict) {
                actions.resetToBoard(conflict.theirs)
            }
        },
        keepMyVersion: () => {
            const { conflict } = values
            if (conflict) {
                actions.rebaseOnBoard(conflict.theirs)
                actions.saveBoard()
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setActiveTab: ({ tabId }) => [
            router.values.location.pathname,
            // While the board loads there is no tab to check the id against, so the requested one stays in the URL.
            { ...router.values.searchParams, tab: values.dashboard ? values.activeTab?.id : tabId },
            router.values.hashParams,
            { replace: true },
        ],
    })),
    urlToAction(({ actions, values }) => ({
        '*': (_, searchParams) => {
            if (searchParams.tab && searchParams.tab !== values.activeTabId) {
                actions.setActiveTab(searchParams.tab)
            }
        },
    })),
    afterMount(({ actions, props, values, cache }) => {
        if (props.uid) {
            actions.loadBoard()
        }
        cache.disposables.add(
            () => {
                const warnIfUnsaved = (event: BeforeUnloadEvent): void => {
                    if (values.saveState && values.saveState !== 'saved') {
                        event.preventDefault()
                    }
                }
                window.addEventListener('beforeunload', warnIfUnsaved)
                return () => window.removeEventListener('beforeunload', warnIfUnsaved)
                // A tab closed while hidden still has its edits to lose.
            },
            'warnIfUnsaved',
            { pauseOnPageHidden: false }
        )
    }),
    beforeUnmount(({ props, values }) => {
        // Leaving the scene cancels the save that waits out `SAVE_DELAY_MS`, so it is sent now. Nothing is left to show
        // whether it worked.
        const { board, dashboard, saveState } = values
        if (props.uid && board && dashboard && (saveState === 'unsaved' || saveState === 'failed')) {
            void updateBoard(props.uid, saveDashboard(dashboard), board.version).catch(() => {})
        }
    }),
])
