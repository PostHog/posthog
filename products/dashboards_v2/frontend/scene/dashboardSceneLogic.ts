// The scene's panel lists share these specs, so edits here and the grid on screen use the same sizes.
const sizeOf = sizeOfPanels(DEFAULT_PANELS)

const projectId = (): string => String(ApiConfig.getCurrentProjectId())

export interface BoardLoadError {
    problem: UnavailableReason
    description?: string
}

const statusOf = (error: unknown): number | undefined => (error as { status?: number } | null)?.status

function boardLoadError(error: unknown): BoardLoadError {
    if (error instanceof UnreadableBoardError) {
        return { problem: 'error', description: error.message }
    }
    const status = statusOf(error)
    if (status === 403) {
        return { problem: 'noAccess' }
    }
    if (status === 404) {
        return { problem: 'notFound' }
    }
    return { problem: 'error', description: "This board couldn't be loaded. Reload the page to try again." }
}

function startFrom(dashboard: Dashboard): DashboardHistory {
    return startHistory(settleDashboard(dashboard, sizeOf))
}

