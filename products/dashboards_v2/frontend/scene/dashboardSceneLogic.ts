export const dashboardSceneLogic = kea<dashboardSceneLogicType>([
    path(['products', 'dashboardsV2', 'scene', 'dashboardSceneLogic']),
    actions({
        /** The one entry point for edits to the layout. Drags and menus call it, so the permission check lives here only. */
        applyDashboardEdit: (edit: DashboardEdit, view?: View) => ({ edit, view }),
        commitDashboard: (dashboard: Dashboard) => ({ dashboard }),
        undo: true,
        redo: true,
        stepHistory: (step: 'back' | 'forward') => ({ step }),
        setActiveTab: (tabId: string) => ({ tabId }),
        loadBoard: (uid: string) => ({ uid }),
        boardLoaded: (uid: string, version: number, dashboard: Dashboard) => ({ uid, version, dashboard }),
        loadBoardFailure: (error: BoardLoadError) => ({ error }),
        showKitchenSink: true,
        saveBoard: true,
        boardSaved: (version: number) => ({ version }),
        saveAsBoard: true,
        saveDone: true,
    }),
    reducers({
        history: [
            // Without a board in the URL the scene shows the Kitchen sink fixture, and edits to it are not saved.
            startFrom(kitchenSinkDashboard) as DashboardHistory,
            {
                commitDashboard: (state, { dashboard }) => recordEdit(state, dashboard),
                stepHistory: (state, { step }) => (step === 'back' ? undoEdit(state) : redoEdit(state)),
                boardLoaded: (_, { dashboard }) => startFrom(dashboard),
                showKitchenSink: () => startFrom(kitchenSinkDashboard),
            },
        ],
        boardUid: [
            null as string | null,
            { loadBoard: (_, { uid }) => uid, boardLoaded: (_, { uid }) => uid, showKitchenSink: () => null },
        ],
        // Sent as `base_version`, so a save never overwrites one made after this board was loaded or last saved.
        boardVersion: [
            null as number | null,
            {
                loadBoard: () => null,
                boardLoaded: (_, { version }) => version,
                boardSaved: (_, { version }) => version,
                showKitchenSink: () => null,
            },
        ],
        boardLoading: [
            false,
            {
                loadBoard: () => true,
                boardLoaded: () => false,
                loadBoardFailure: () => false,
                showKitchenSink: () => false,
            },
        ],
        boardError: [
            null as BoardLoadError | null,
            { loadBoard: () => null, loadBoardFailure: (_, { error }) => error, showKitchenSink: () => null },
        ],
        savingBoard: [false, { saveBoard: () => true, saveAsBoard: () => true, saveDone: () => false }],
        activeTabId: [null as string | null, { setActiveTab: (_, { tabId }) => tabId }],
    }),
    selectors({
        dashboard: [(s) => [s.history], (history: DashboardHistory): Dashboard => history.present],
        canUndo: [(s) => [s.history], (history: DashboardHistory): boolean => history.past.length > 0],
        canRedo: [(s) => [s.history], (history: DashboardHistory): boolean => history.future.length > 0],
        disabledReasonFor: [
            (s) => [s.dashboard],
            // Every edit needs Editor, as on v1 dashboards. When the dashboard has no `user_access_level`, this
            // falls back to the project-wide dashboard level.
            (dashboard: Dashboard): ((action: DashboardAction) => string | null) =>
                () =>
                    getAccessControlDisabledReason(
                        AccessControlResourceType.Dashboard,
                        AccessControlLevel.Editor,
                        dashboard.user_access_level,
                        false
                    ),
        ],
        activeTab: [
            (s) => [s.dashboard, s.activeTabId],
            (dashboard: Dashboard, activeTabId: string | null): GridTab => activeGridTab(dashboard, activeTabId),
        ],
    }),
    listeners(({ actions, values }) => ({
        loadBoard: async ({ uid }, breakpoint) => {
            try {
                const board = await dashboardV2BoardsRetrieve(projectId(), uid)
                breakpoint()
                // Going back to the fixture does not call `loadBoard`, so the breakpoint alone would let this land on it.
                if (values.boardUid !== uid) {
                    return
                }
                actions.boardLoaded(uid, board.version, loadDashboard(upgradeBoard(board.spec)))
            } catch (error) {
                breakpoint()
                if (values.boardUid !== uid) {
                    return
                }
                actions.loadBoardFailure(boardLoadError(error))
            }
        },
        saveBoard: async () => {
            const uid = values.boardUid
            if (uid === null || values.boardLoading || values.boardError) {
                actions.saveDone()
                return
            }
            try {
                const board = await dashboardV2BoardsUpdate(projectId(), uid, {
                    spec: boardDocument(values.dashboard),
                    base_version: values.boardVersion ?? undefined,
                })
                // A board opened while this one saved has its own version.
                if (values.boardUid === uid) {
                    actions.boardSaved(board.version)
                }
                lemonToast.success('Board saved')
            } catch (error) {
                lemonToast.error(
                    statusOf(error) === 409
                        ? 'Someone saved this board after you opened it. Reload the page to see their changes.'
                        : "The board couldn't be saved. Try again."
                )
            } finally {
                actions.saveDone()
            }
        },
        saveAsBoard: async () => {
            const savedFrom = router.values.location.pathname
            try {
                const board = await dashboardV2BoardsCreate(projectId(), { spec: boardDocument(values.dashboard) })
                lemonToast.success('Saved as a board')
                // A slow save must not pull someone out of the page they moved on to.
                if (router.values.location.pathname === savedFrom) {
                    router.actions.push(urls.dashboardV2Board(board.uid))
                }
            } catch {
                lemonToast.error("The board couldn't be saved. Try again.")
            } finally {
                actions.saveDone()
            }
        },
        applyDashboardEdit: ({ edit, view }) => {
            if (values.disabledReasonFor(edit.edit)) {
                return
            }
            const next = applyEdit(values.dashboard, edit, sizeOf, view)
            if (recordEdit(values.history, next) === values.history) {
                return
            }
            // With no tab in the URL the first tab shows, so a reorder would switch tabs unless the shown one is pinned.
            if (edit.edit === 'moveTab' && values.activeTabId === null) {
                actions.setActiveTab(values.activeTab.id)
            }
            actions.commitDashboard(next)
            if (edit.edit === 'addTab') {
                actions.setActiveTab(next.tabs[next.tabs.length - 1].id)
            }
        },
        undo: () => {
            if (!values.disabledReasonFor('undo')) {
                actions.stepHistory('back')
            }
        },
        redo: () => {
            if (!values.disabledReasonFor('redo')) {
                actions.stepHistory('forward')
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setActiveTab: ({ tabId }) => [
            router.values.location.pathname,
            // While a board loads, its tabs are not known yet, so the requested tab is kept as asked.
            { ...router.values.searchParams, tab: values.boardLoading ? tabId : values.activeTab.id },
            router.values.hashParams,
            { replace: true },
        ],
    })),
    urlToAction(({ actions, values }) => {
        const followTab = (tab: string | undefined): void => {
            if (tab && tab !== values.activeTabId) {
                actions.setActiveTab(tab)
            }
        }
        return {
            [urls.dashboardV2Board(':uid')]: ({ uid }, searchParams) => {
                if (uid && uid !== values.boardUid) {
                    actions.loadBoard(uid)
                }
                followTab(searchParams.tab)
            },
            [urls.dashboardV2()]: (_, searchParams) => {
                if (values.boardUid !== null || values.boardError !== null) {
                    actions.showKitchenSink()
                }
                followTab(searchParams.tab)
            },
        }
    }),
])
