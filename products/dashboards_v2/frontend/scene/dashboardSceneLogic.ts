// The scene's panel lists share these specs, so edits here and the grid on screen use the same sizes.
const sizeOf = sizeOfPanels(DEFAULT_PANELS)

const SAVE_DELAY_MS = 1000

export interface DashboardSceneLogicProps {
    /** The board to load and save. Without one, the scene shows the kitchen sink fixture and saves nothing. */
    uid?: string
}

export type SaveState = 'saved' | 'unsaved' | 'saving' | 'failed' | 'conflict'

/** Someone else saved the board after this person's last save. Nothing of theirs is saved until they pick a side. */
export type BoardConflict = {
    theirs: Board
    /** The dashboard both sides started from: the one this person last loaded or saved. */
    base: Dashboard
}

// The boards API stores a document as the client sent it, so a board can lack the shape of a dashboard.
async function getDashboardBoard(uid: string): Promise<Board> {
    const board = await getBoard(uid)
    if (!isDashboardDocument(board.spec)) {
        throw new Error('The board is not a dashboard document')
    }
    return board
}

function dashboardOf(board: Board): Dashboard {
    // Anyone who saves the board writes its spec, so an access level in it is not this viewer's. Dropping it here
    // also keeps it out of every save.
    const { user_access_level: _, ...spec } = board.spec
    return settleDashboard(loadDashboard(spec), sizeOf)
}

function unavailableReason(error: unknown): UnavailableReason {
    const status = error instanceof ApiError ? error.status : undefined
    if (status === 404) {
        return 'notFound'
    }
    return status === 403 ? 'noAccess' : 'error'
}

