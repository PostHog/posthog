import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { type Dashboard, type GridTab, activeGridTab } from '../dashboard/document/dashboardTypes'
import type { DashboardEdit, View } from '../dashboard/edits/dashboardEdits'
import { type SavedDashboardLogicProps, savedDashboardLogic } from '../dashboard/saved/savedDashboardLogic'
import { kitchenSinkDashboard } from '../fixtures/kitchenSinkDashboard'

export interface DashboardSceneLogicProps {
    /** The board to load and save. Without one, the scene shows the kitchen sink fixture and saves nothing. */
    uid?: string
}

export function savedDashboardLogicProps({ uid }: DashboardSceneLogicProps): SavedDashboardLogicProps {
    // TODO(2026-11-23): Delete the kitchen sink fixture once the board list can open saved boards.
    // Without a board in the URL, the scene shows the fixture and saves nothing.
    return uid ? { uid } : { initialDashboard: kitchenSinkDashboard }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardSceneLogicValues {
    dashboard: Dashboard | null // saved
    activeTab: GridTab | null
    activeTabId: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardSceneLogicActions {
    applySavedEdit: (
        edit: DashboardEdit,
        view?: View | undefined
    ) => {
        edit: DashboardEdit
        view: View | undefined
    } // saved
    applyDashboardEdit: (
        edit: DashboardEdit,
        view?: View
    ) => {
        edit: DashboardEdit
        view: View | undefined
    }
    setActiveTab: (tabId: string) => {
        tabId: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardSceneLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        activeTab: (dashboard: Dashboard | null, activeTabId: string | null) => GridTab | null
    }
}

export type dashboardSceneLogicType = MakeLogicType<
    dashboardSceneLogicValues,
    dashboardSceneLogicActions,
    DashboardSceneLogicProps,
    dashboardSceneLogicMeta
>

/** The scene's own layer over `savedDashboardLogic`: which tab shows, kept in the URL. */
export const dashboardSceneLogic = kea<dashboardSceneLogicType>([
    props({} as DashboardSceneLogicProps),
    key((props) => props.uid ?? 'fixture'),
    path((key) => ['products', 'dashboardsV2', 'scene', 'dashboardSceneLogic', key]),
    connect((props: DashboardSceneLogicProps) => {
        const saved = savedDashboardLogic(savedDashboardLogicProps(props))
        return { values: [saved, ['dashboard']], actions: [saved, ['applyDashboardEdit as applySavedEdit']] }
    }),
    actions({
        applyDashboardEdit: (edit: DashboardEdit, view?: View) => ({ edit, view }),
        setActiveTab: (tabId: string) => ({ tabId }),
    }),
    reducers({
        activeTabId: [null as string | null, { setActiveTab: (_, { tabId }) => tabId }],
    }),
    selectors({
        activeTab: [
            (s) => [s.dashboard, s.activeTabId],
            (dashboard: Dashboard | null, activeTabId: string | null): GridTab | null =>
                dashboard && activeGridTab(dashboard, activeTabId),
        ],
    }),
    listeners(({ actions, values }) => ({
        applyDashboardEdit: ({ edit, view }) => {
            const { dashboard, activeTab, activeTabId } = values
            actions.applySavedEdit(edit, view)
            const next = values.dashboard
            if (!next || next === dashboard) {
                return
            }
            // With no tab in the URL the first tab shows, so a reorder would switch tabs unless the shown one is pinned.
            if (edit.edit === 'moveTab' && activeTabId === null && activeTab) {
                actions.setActiveTab(activeTab.id)
            }
            if (edit.edit === 'addTab') {
                actions.setActiveTab(next.tabs[next.tabs.length - 1].id)
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setActiveTab: ({ tabId }) => [
            router.values.location.pathname,
            // While the board loads there is no tab to check the id against, so the requested one stays in the URL.
            { ...router.values.searchParams, tab: values.dashboard ? values.activeTab?.id : tabId },
            router.values.hashParams,
            { replace: true },
        ],
    })),
    urlToAction(({ actions, values }) => ({
        '*': (_, searchParams) => {
            if (searchParams.tab && searchParams.tab !== values.activeTabId) {
                actions.setActiveTab(searchParams.tab)
            }
        },
    })),
])
