import { MakeLogicType, actions, kea, listeners, path, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { getAccessControlDisabledReason } from 'lib/utils/accessControlUtils'

import { AccessControlLevel, AccessControlResourceType } from '~/types'

import type { DashboardAction } from '../dashboard/dashboardContext'
import { type Dashboard, type GridTab, activeGridTab } from '../dashboard/document/dashboardTypes'
import { type DashboardEdit, type View, applyEdit, settleDashboard } from '../dashboard/edits/dashboardEdits'
import {
    type DashboardHistory,
    recordEdit,
    redoEdit,
    startHistory,
    undoEdit,
} from '../dashboard/edits/dashboardHistory'
import { kitchenSinkDashboard } from '../fixtures/kitchenSinkDashboard'
import { DEFAULT_WIDGETS } from '../widgets/defaultWidgets'
import { sizeOfWidgets } from '../widgets/widgetSpec'

// The scene passes the same list to the view, so edits here and the grid on screen use the same sizes.
const sizeOf = sizeOfWidgets(DEFAULT_WIDGETS)

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardSceneLogicValues {
    activeTab: GridTab
    activeTabId: string | null
    canRedo: boolean
    canUndo: boolean
    dashboard: Dashboard
    disabledReasonFor: (action: DashboardAction) => string | null
    history: DashboardHistory
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardSceneLogicActions {
    applyDashboardEdit: (
        edit: DashboardEdit,
        view?: View
    ) => {
        edit: DashboardEdit
        view: View | undefined
    }
    commitDashboard: (dashboard: Dashboard) => {
        dashboard: Dashboard
    }
    redo: () => {
        value: true
    }
    setActiveTab: (tabId: string) => {
        tabId: string
    }
    stepHistory: (step: 'back' | 'forward') => {
        step: 'back' | 'forward'
    }
    undo: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        dashboard: (history: DashboardHistory) => Dashboard
        canUndo: (history: DashboardHistory) => boolean
        canRedo: (history: DashboardHistory) => boolean
        disabledReasonFor: (dashboard: Dashboard) => (action: DashboardAction) => string | null
        activeTab: (dashboard: Dashboard, activeTabId: string | null) => GridTab
    }
}

export type dashboardSceneLogicType = MakeLogicType<
    dashboardSceneLogicValues,
    dashboardSceneLogicActions,
    Record<string, any>,
    dashboardSceneLogicMeta
>

export const dashboardSceneLogic = kea<dashboardSceneLogicType>([
    path(['products', 'dashboardsV2', 'scene', 'dashboardSceneLogic']),
    actions({
        /** The one entry point for edits to the layout. Drags and menus call it, so the permission check lives here only. */
        applyDashboardEdit: (edit: DashboardEdit, view?: View) => ({ edit, view }),
        commitDashboard: (dashboard: Dashboard) => ({ dashboard }),
        undo: true,
        redo: true,
        stepHistory: (step: 'back' | 'forward') => ({ step }),
        setActiveTab: (tabId: string) => ({ tabId }),
    }),
    reducers({
        history: [
            // TODO(2026-11-23): Load the dashboard from the API and save edits back to it.
            // The kitchen sink fixture is temporary. The scene starts from it on every load, so no edit is saved.
            startHistory(settleDashboard(kitchenSinkDashboard, sizeOf)) as DashboardHistory,
            {
                commitDashboard: (state, { dashboard }) => recordEdit(state, dashboard),
                stepHistory: (state, { step }) => (step === 'back' ? undoEdit(state) : redoEdit(state)),
            },
        ],
        activeTabId: [null as string | null, { setActiveTab: (_, { tabId }) => tabId }],
    }),
    selectors({
        dashboard: [(s) => [s.history], (history: DashboardHistory): Dashboard => history.present],
        canUndo: [(s) => [s.history], (history: DashboardHistory): boolean => history.past.length > 0],
        canRedo: [(s) => [s.history], (history: DashboardHistory): boolean => history.future.length > 0],
        disabledReasonFor: [
            (s) => [s.dashboard],
            // Every edit needs Editor, as on v1 dashboards. When the dashboard has no `user_access_level`, this
            // falls back to the project-wide dashboard level.
            (dashboard: Dashboard): ((action: DashboardAction) => string | null) =>
                () =>
                    getAccessControlDisabledReason(
                        AccessControlResourceType.Dashboard,
                        AccessControlLevel.Editor,
                        dashboard.user_access_level,
                        false
                    ),
        ],
        activeTab: [
            (s) => [s.dashboard, s.activeTabId],
            (dashboard: Dashboard, activeTabId: string | null): GridTab => activeGridTab(dashboard, activeTabId),
        ],
    }),
    listeners(({ actions, values }) => ({
        applyDashboardEdit: ({ edit, view }) => {
            if (values.disabledReasonFor(edit.edit)) {
                return
            }
            const next = applyEdit(values.dashboard, edit, sizeOf, view)
            if (recordEdit(values.history, next) === values.history) {
                return
            }
            // With no tab in the URL the first tab shows, so a reorder would switch tabs unless the shown one is pinned.
            if (edit.edit === 'moveTab' && values.activeTabId === null) {
                actions.setActiveTab(values.activeTab.id)
            }
            actions.commitDashboard(next)
            if (edit.edit === 'addTab') {
                actions.setActiveTab(next.tabs[next.tabs.length - 1].id)
            }
        },
        undo: () => {
            if (!values.disabledReasonFor('undo')) {
                actions.stepHistory('back')
            }
        },
        redo: () => {
            if (!values.disabledReasonFor('redo')) {
                actions.stepHistory('forward')
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setActiveTab: () => [
            router.values.location.pathname,
            { ...router.values.searchParams, tab: values.activeTab.id },
            router.values.hashParams,
            { replace: true },
        ],
    })),
    urlToAction(({ actions, values }) => ({
        '*': (_, searchParams) => {
            if (searchParams.tab && searchParams.tab !== values.activeTabId) {
                actions.setActiveTab(searchParams.tab)
            }
        },
    })),
])
