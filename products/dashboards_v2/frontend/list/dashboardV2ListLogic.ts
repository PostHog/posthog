export type dashboardV2ListLogicType = MakeLogicType<
    dashboardV2ListLogicValues,
    dashboardV2ListLogicActions,
    Record<string, any>,
    dashboardV2ListLogicMeta
>

export const dashboardV2ListLogic = kea<dashboardV2ListLogicType>([
    path(['products', 'dashboards_v2', 'frontend', 'list', 'dashboardV2ListLogic']),

    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),

    actions({
        setSearch: (search: string) => ({ search }),
        setNewDialogOpen: (open: boolean) => ({ open }),
        setCreateErrors: (errors: string[]) => ({ errors }),
    }),

    loaders(({ values }) => ({
        dashboardPage: [
            null as PaginatedDashboardV2SummaryListApi | null,
            {
                loadDashboards: async (search: string, breakpoint) => {
                    const page = await dashboardsV2List(String(values.currentProjectId), {
                        search: search || undefined,
                        limit: DASHBOARD_LIST_LIMIT,
                    })
                    breakpoint()
                    return page
                },
            },
        ],
        createdDashboard: [
            null as DashboardV2DetailApi | null,
            {
                createDashboard: async ({ title, json }: { title: string; json: string }) => {
                    const projectId = String(values.currentProjectId)
                    if (json.trim()) {
                        return await dashboardsV2Create(projectId, { spec: JSON.parse(json) })
                    }
                    try {
                        return await dashboardsV2Create(projectId, { spec: blankDashboardSpec(title) })
                    } catch (error: any) {
                        if (error?.status !== 409) {
                            throw error
                        }
                        const suffix = Math.random().toString(36).slice(2, 6)
                        return await dashboardsV2Create(projectId, { spec: blankDashboardSpec(title, suffix) })
                    }
                },
            },
        ],
    })),

    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        loadedSearch: ['', { loadDashboardsSuccess: (_, { payload }) => payload ?? '' }],
        newDialogOpen: [
            false,
            {
                setNewDialogOpen: (_, { open }) => open,
                createDashboardSuccess: () => false,
            },
        ],
        createErrors: [
            [] as string[],
            {
                setCreateErrors: (_, { errors }) => errors,
                createDashboard: () => [],
                setNewDialogOpen: () => [],
            },
        ],
        loadFailed: [
            false,
            {
                loadDashboards: () => false,
                loadDashboardsFailure: () => true,
            },
        ],
    }),

    selectors({
        dashboards: [
            (s) => [s.dashboardPage],
            (dashboardPage: PaginatedDashboardV2SummaryListApi | null): DashboardV2SummaryApi[] | null =>
                dashboardPage?.results ?? null,
        ],
        hasMore: [
            (s) => [s.dashboardPage],
            (dashboardPage: PaginatedDashboardV2SummaryListApi | null): boolean => !!dashboardPage?.next,
        ],
    }),

    listeners(({ actions }) => ({
        setSearch: async ({ search }, breakpoint) => {
            await breakpoint(250)
            actions.loadDashboards(search)
        },
        createDashboardSuccess: ({ createdDashboard, payload }) => {
            if (!createdDashboard) {
                return
            }
            // pinned: analytics event name. Renaming it breaks the insights built on it.
            posthog.capture('dashboard v2 created', { source: payload?.json.trim() ? 'json' : 'blank' })
            router.actions.push(urls.dashboardV2(createdDashboard.uid))
        },
        createDashboardFailure: ({ errorObject }) => {
            actions.setCreateErrors(
                errorObject instanceof SyntaxError
                    ? [`This is not valid JSON: ${errorObject.message}`]
                    : specErrorMessages(errorObject, "Couldn't create the dashboard. Try again.")
            )
        },
    })),

    afterMount(({ actions }) => {
        actions.loadDashboards('')
    }),
])
