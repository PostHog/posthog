import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import posthog from 'lib/posthog-typed'
import { projectLogic } from 'scenes/projectLogic'
import { urls } from 'scenes/urls'

import { dashboardsV2Create, dashboardsV2List } from '../generated/api'
import type {
    DashboardV2DetailApi,
    DashboardV2SummaryApi,
    PaginatedDashboardV2SummaryListApi,
} from '../generated/api.schemas'
import { specErrorMessages } from '../specErrors'
import { blankDashboardSpec } from './blankDashboardSpec'

export const DASHBOARD_LIST_LIMIT = 200

