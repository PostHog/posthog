    dashboardPage: PaginatedDashboardV2SummaryListApi | null
    dashboardPageLoading: boolean
    dashboards: DashboardV2SummaryApi[] | null
    hasMore: boolean
    loadFailed: boolean
    loadedSearch: string
    newDialogOpen: boolean
    search: string
