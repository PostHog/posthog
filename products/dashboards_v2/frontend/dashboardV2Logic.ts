/** Why a board in the URL isn't showing, in the words `DashboardV2Unavailable` shows. */
export interface BoardLoadError {
    problem: DashboardV2Problem
    /** Replaces the problem's default description. */
    description?: string
}

function boardLoadError(error: unknown): BoardLoadError {
    if (error instanceof UnreadableBoardError) {
        return { problem: 'notFound', description: error.message }
    }
    const status = (error as { status?: number } | null)?.status
    if (status === 403) {
        return { problem: 'noAccess' }
    }
    if (status === 404) {
        return { problem: 'notFound' }
    }
    return { problem: 'notFound', description: 'This board could not be loaded. Reload the page to try again.' }
}

function startFrom(dashboard: Dashboard): DashboardHistory {
    return startHistory(settleDashboard(dashboard, sizeOf))
}

