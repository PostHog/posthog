export type dashboardV2LogicType = MakeLogicType<
    dashboardV2LogicValues,
    dashboardV2LogicActions,
    Record<string, any>,
    dashboardV2LogicMeta
>

export const dashboardV2Logic = kea<dashboardV2LogicType>([
    path(['products', 'dashboardsV2', 'dashboardV2Logic']),
    actions({
        /** The one entry point for edits to the layout. Drags and menus call it, so the permission check lives here only. */
        applyDashboardEdit: (edit: DashboardEdit) => ({ edit }),
        commitDashboard: (dashboard: Dashboard) => ({ dashboard }),
        undo: true,
        redo: true,
        stepHistory: (step: 'back' | 'forward') => ({ step }),
        setActiveTab: (tabId: string) => ({ tabId }),
        setDropTarget: (dropTarget: DropTarget | null) => ({ dropTarget }),
    }),
    reducers({
        history: [
            { past: [], present: settleDashboard(kitchenSinkDashboard), future: [] } as History,
            {
                commitDashboard: (state, { dashboard }) => commit(state, dashboard),
                stepHistory: (state, { step }) => {
                    if (step === 'back' && state.past.length > 0) {
                        return {
                            past: state.past.slice(0, -1),
                            present: state.past[state.past.length - 1],
                            future: [state.present, ...state.future],
                        }
                    }
                    if (step === 'forward' && state.future.length > 0) {
                        return {
                            past: [...state.past, state.present],
                            present: state.future[0],
                            future: state.future.slice(1),
                        }
                    }
                    return state
                },
            },
        ],
        activeTabId: [null as string | null, { setActiveTab: (_, { tabId }) => tabId }],
        dropTarget: [
            null as DropTarget | null,
            { setDropTarget: (_, { dropTarget }) => dropTarget, commitDashboard: () => null },
        ],
    }),
    selectors({
        dashboard: [(s) => [s.history], (history: History): Dashboard => history.present],
        canUndo: [(s) => [s.history], (history: History): boolean => history.past.length > 0],
        canRedo: [(s) => [s.history], (history: History): boolean => history.future.length > 0],
        /** Every permission check goes through this, so the rules live in `access/dashboardV2Access.ts` only. */
        disabledReasonFor: [
            (s) => [s.dashboard],
            (dashboard: Dashboard): ((action: DashboardV2Action) => string | null) =>
                (action) =>
                    dashboardV2DisabledReason(action, dashboard.user_access_level),
        ],
        canEditLayout: [
            (s) => [s.disabledReasonFor],
            (disabledReasonFor: (action: DashboardV2Action) => string | null): boolean =>
                disabledReasonFor('placeTiles') === null,
        ],
        activeTab: [
            (s) => [s.dashboard, s.activeTabId],
            (dashboard: Dashboard, activeTabId: string | null): DashboardTab =>
                dashboard.tabs.find((tab) => tab.id === activeTabId) ?? dashboard.tabs[0],
        ],
    }),
    listeners(({ actions, values }) => ({
        applyDashboardEdit: ({ edit }) => {
            if (values.disabledReasonFor(edit.edit)) {
                return
            }
            const next = applyEdit(values.dashboard, edit)
            // A press that moved nothing must not add an undo step or clear what could be redone.
            if (objectsEqual(next, values.dashboard)) {
                return
            }
            actions.commitDashboard(next)
            if (edit.edit === 'addTab') {
                actions.setActiveTab(next.tabs[next.tabs.length - 1].id)
            }
        },
        undo: () => {
            if (!values.disabledReasonFor('undo')) {
                actions.stepHistory('back')
            }
        },
        redo: () => {
            if (!values.disabledReasonFor('redo')) {
                actions.stepHistory('forward')
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setActiveTab: () => [
            router.values.location.pathname,
            { ...router.values.searchParams, tab: values.activeTab.id },
            router.values.hashParams,
            { replace: true },
        ],
    })),
    urlToAction(({ actions, values }) => ({
        '*': (_, searchParams) => {
            if (searchParams.tab && searchParams.tab !== values.activeTabId) {
                actions.setActiveTab(searchParams.tab)
            }
        },
    })),
])
