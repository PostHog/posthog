export const dashboardV2Logic = kea<dashboardV2LogicType>([
    path(['products', 'dashboardsV2', 'dashboardV2Logic']),
    actions({
        /** The one entry point for edits to the layout. Drags and menus call it, so the permission check lives here only. */
        applyDashboardEdit: (edit: DashboardEdit, view?: View) => ({ edit, view }),
        commitDashboard: (dashboard: Dashboard) => ({ dashboard }),
        undo: true,
        redo: true,
        stepHistory: (step: 'back' | 'forward') => ({ step }),
        setActiveTab: (tabId: string) => ({ tabId }),
    }),
    reducers({
        history: [
            // TODO(2026-11-23): Load the dashboard from the API and save edits back to it.
            // The kitchen sink fixture is temporary. The scene starts from it on every load, so no edit is saved.
            startHistory(settleDashboard(kitchenSinkDashboard, sizeOf)) as DashboardHistory,
            {
                commitDashboard: (state, { dashboard }) => recordEdit(state, dashboard),
                stepHistory: (state, { step }) => (step === 'back' ? undoEdit(state) : redoEdit(state)),
            },
        ],
        activeTabId: [null as string | null, { setActiveTab: (_, { tabId }) => tabId }],
    }),
    selectors({
        dashboard: [(s) => [s.history], (history: DashboardHistory): Dashboard => history.present],
        canUndo: [(s) => [s.history], (history: DashboardHistory): boolean => history.past.length > 0],
        canRedo: [(s) => [s.history], (history: DashboardHistory): boolean => history.future.length > 0],
        disabledReasonFor: [
            (s) => [s.dashboard],
            (dashboard: Dashboard): ((action: DashboardV2Action) => string | null) =>
                (action) =>
                    dashboardV2DisabledReason(action, dashboard.user_access_level),
        ],
        activeTab: [
            (s) => [s.dashboard, s.activeTabId],
            (dashboard: Dashboard, activeTabId: string | null): GridTab => activeGridTab(dashboard, activeTabId),
        ],
    }),
    listeners(({ actions, values }) => ({
        applyDashboardEdit: ({ edit, view }) => {
            if (values.disabledReasonFor(edit.edit)) {
                return
            }
            const next = applyEdit(values.dashboard, edit, sizeOf, view)
            if (recordEdit(values.history, next) === values.history) {
                return
            }
            // With no tab in the URL the first tab shows, so a reorder would switch tabs unless the shown one is pinned.
            if (edit.edit === 'moveTab' && values.activeTabId === null) {
                actions.setActiveTab(values.activeTab.id)
            }
            actions.commitDashboard(next)
            if (edit.edit === 'addTab') {
                actions.setActiveTab(next.tabs[next.tabs.length - 1].id)
            }
        },
        undo: () => {
            if (!values.disabledReasonFor('undo')) {
                actions.stepHistory('back')
            }
        },
        redo: () => {
            if (!values.disabledReasonFor('redo')) {
                actions.stepHistory('forward')
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setActiveTab: () => [
            router.values.location.pathname,
            { ...router.values.searchParams, tab: values.activeTab.id },
            router.values.hashParams,
            { replace: true },
        ],
    })),
    urlToAction(({ actions, values }) => ({
        '*': (_, searchParams) => {
            if (searchParams.tab && searchParams.tab !== values.activeTabId) {
                actions.setActiveTab(searchParams.tab)
            }
        },
    })),
])
