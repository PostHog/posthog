type LayoutItem = DashboardV2LayoutApi['items'][number]

const SAVE_QUIET_MS = 500
const NEW_PANEL_SIZE = { w: 12, h: 8 }

function samePanel(a: unknown, b: unknown): boolean {
    return objectsEqual(JSON.parse(JSON.stringify(a)), JSON.parse(JSON.stringify(b)))
}

function placedIds(items: LayoutItem[]): string[] {
    return items.flatMap((item) =>
        'panel' in item
            ? [item.panel]
            : 'row' in item
              ? item.items.map((placed) => placed.panel)
              : item.items.flatMap((tab) => tab.items.map((placed) => placed.panel))
    )
}

function inRowsAndTabs(
    items: LayoutItem[],
    change: (list: DashboardV2PanelItemApi[]) => DashboardV2PanelItemApi[]
): LayoutItem[] {
    return items.map((item) =>
        'row' in item
            ? { ...item, items: change(item.items) }
            : 'tabs' in item
              ? { ...item, items: item.items.map((tab) => ({ ...tab, items: change(tab.items) })) }
              : item
    )
}

function withoutPanel(items: LayoutItem[], id: string): LayoutItem[] {
    return inRowsAndTabs(
        items.filter((item) => !('panel' in item && item.panel === id)),
        (list) => list.filter((item) => item.panel !== id)
    )
}

function placedBelow<Item extends { y: number }>(
    list: Item[],
    source: DashboardV2PanelItemApi,
    id: string
): (Item | DashboardV2PanelItemApi)[] {
    const y = source.y + source.h
    return [
        ...list.map((item) => (item.y >= y ? { ...item, y: item.y + source.h } : item)),
        { ...source, panel: id, y },
    ]
}

function withPanelPlaced(items: LayoutItem[], id: string, near?: string): LayoutItem[] {
    const beside = items.find((item): item is DashboardV2PanelItemApi => 'panel' in item && item.panel === near)
    if (beside) {
        return placedBelow(items, beside, id)
    }
    if (near && placedIds(items).includes(near)) {
        return inRowsAndTabs(items, (list) => {
            const source = list.find((item) => item.panel === near)
            return source ? placedBelow(list, source, id) : list
        })
    }
    const y = items.reduce((bottom, item) => Math.max(bottom, item.y + ('panel' in item ? item.h : 1)), 0)
    return [...items, { panel: id, x: 0, y, ...NEW_PANEL_SIZE }]
}

function applyWrite(spec: DashboardV2SpecApi, { id, panel, near }: PanelWrite): DashboardV2SpecApi {
    const placed = placedIds(spec.layout.items).includes(id)
    if (!panel) {
        if (!placed && !(id in spec.panels)) {
            return spec
        }
        const { [id]: _removed, ...panels } = spec.panels
        return { ...spec, panels, layout: { ...spec.layout, items: withoutPanel(spec.layout.items, id) } }
    }
    if (placed && id in spec.panels && samePanel(spec.panels[id], panel)) {
        return spec
    }
    return {
        ...spec,
        panels: { ...spec.panels, [id]: panel },
        layout: placed ? spec.layout : { ...spec.layout, items: withPanelPlaced(spec.layout.items, id, near) },
    }
}

function freePanelId(taken: Set<string>, base: string): string {
    let index = 1
    while (taken.has(`${base}_${index}`)) {
        index++
    }
    return `${base}_${index}`
}

function followSpec(editing: PanelEditing | null, dashboard: DashboardV2DetailApi): PanelEditing | null {
    return editing && !editing.panel && !(editing.id in dashboard.spec.panels) ? null : editing
}

