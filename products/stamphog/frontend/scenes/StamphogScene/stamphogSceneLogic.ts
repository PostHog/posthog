// Carries the user's installation pick across the authorize redirect: the OAuth code is single-use
// and consumed server-side before installations are known, so the choice can't ride the request
// that discovered them — it rides the browser instead, and the explicit-id path verifies it.
const PENDING_INSTALLATION_STORAGE_KEY = 'stamphog-pending-installation-id'

// Large enough that an organization-wide install loads in one request. The list endpoint sets no max limit.
const REPO_CONFIGS_PAGE_SIZE = 1000

// Every table row mounts two switches and a select, so mounting an org's worth of rows stalls the page
// for a noticeable moment on each search or filter change. Search is how people find a repo among
// hundreds, so the table renders the first matches and offers the full list on request.
const VISIBLE_REPO_LIMIT = 100

export type RepoStatusFilter = 'all' | 'on' | 'off'

function isRepoOn(repo: StamphogRepoConfigApi): boolean {
    return !!repo.enabled || !!repo.digest_enabled
}

