// Carries the user's installation pick across the authorize redirect: the OAuth code is single-use
// and consumed server-side before installations are known, so the choice can't ride the request
// that discovered them — it rides the browser instead, and the explicit-id path verifies it.
const PENDING_INSTALLATION_STORAGE_KEY = 'stamphog-pending-installation-id'

// Large enough that every added repository loads in one request. The list endpoint sets no max limit.
const REPO_CONFIGS_PAGE_SIZE = 1000

const AVAILABLE_REPOSITORIES_LIMIT = 50
const AVAILABLE_SEARCH_DEBOUNCE_MS = 300

function sortByRepository(repos: StamphogRepoConfigApi[]): StamphogRepoConfigApi[] {
    return [...repos].sort((a, b) => a.repository.localeCompare(b.repository))
}

// The install_info state token expires, and the page can stay open for longer than that. So every
// redirect fetches a fresh URL instead of reading the one the page loaded on mount.
async function redirectToGitHub(projectId: string, target: 'authorize_url' | 'install_url'): Promise<boolean> {
    try {
        const info = await stamphogRepoConfigsInstallInfoRetrieve(projectId)
        const url = info[target]
        if (url) {
            window.location.href = url
            return true
        }
        lemonToast.error('The Stamphog GitHub App is not configured, so it cannot connect.')
    } catch {
        lemonToast.error('Could not load GitHub connection details. Try again.')
    }
    return false
}

