export const stamphogSceneLogic = kea<stamphogSceneLogicType>([
    path(['products', 'stamphog', 'frontend', 'scenes', 'StamphogScene', 'stamphogSceneLogic']),

    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),

    actions({
        // Declared here because the loader takes a breakpoint: typegen would otherwise infer a required
        // payload from its first parameter, and every `loadRepoConfigs()` call would stop compiling.
        loadRepoConfigs: true,
        updateRepoConfig: (id: string, patch: PatchedStamphogRepoConfigWriteApi) => ({ id, patch }),
        repoUpdateDone: (id: string) => ({ id }),
        repoConfigUpdated: (config: StamphogRepoConfigApi) => ({ config }),
        setRepoSearch: (search: string) => ({ search }),
        setRepoExpanded: (id: string, expanded: boolean) => ({ id, expanded }),
        connectInstallation: (installationId: string) => ({ installationId }),
        openInstallPage: true,
        openInstallPageFailed: true,
        refreshFromGitHub: true,
        refreshFromGitHubFailed: true,
        setAvailableSearch: (search: string) => ({ search }),
        setRepositoryToAdd: (repository: string | null) => ({ repository }),
        addRepository: true,
        addRepositorySuccess: (config: StamphogRepoConfigApi) => ({ config }),
        addRepositoryFailure: true,
    }),

    loaders(({ values }) => ({
        repoConfigs: [
            [] as StamphogRepoConfigApi[],
            {
                loadRepoConfigs: async (_, breakpoint) => {
                    // Fetch every page, because the table searches this list client-side and a truncated
                    // first page would hide repositories that nobody could then find.
                    const all: StamphogRepoConfigApi[] = []
                    for (let offset = 0; ; offset += REPO_CONFIGS_PAGE_SIZE) {
                        const response = await stamphogRepoConfigsList(String(values.currentProjectId), {
                            limit: REPO_CONFIGS_PAGE_SIZE,
                            offset,
                        })
                        all.push(...response.results)
                        if (all.length >= response.count || response.results.length === 0) {
                            break
                        }
                    }
                    breakpoint()
                    // A read replica can trail the add, so keep a row this page added until the list has it.
                    const fetchedIds = new Set(all.map((repo) => repo.id))
                    const addedHere = values.repoConfigs.filter(
                        (repo) => values.addedRepoIds.includes(repo.id) && !fetchedIds.has(repo.id)
                    )
                    return sortByRepository([...all, ...addedHere])
                },
            },
        ],
        installInfo: [
            null as StamphogInstallInfoApi | null,
            {
                loadInstallInfo: async () => {
                    return stamphogRepoConfigsInstallInfoRetrieve(String(values.currentProjectId))
                },
            },
        ],
        // Null until the first answer, so the page can tell "not connected" apart from "not known yet".
        availableRepositories: [
            null as StamphogAvailableRepositoriesApi | null,
            {
                loadAvailableRepositories: async ({ search }: { search: string }, breakpoint) => {
                    const response = await stamphogRepoConfigsAvailableRepositoriesRetrieve(
                        String(values.currentProjectId),
                        { search: search.trim(), limit: AVAILABLE_REPOSITORIES_LIMIT }
                    )
                    // Drop a slow response once a newer search has started.
                    breakpoint()
                    return response
                },
            },
        ],
        // Sync is a loader so the button can wire its in-flight state off
        // syncResultLoading and guard double-submission during the callback.
        syncResult: [
            null as StamphogSyncInstallationResponseApi | null,
            {
                syncInstallation: async ({
                    installationId,
                    code,
                    state,
                }: {
                    // Optional: absent when the callback carries only a code, where the backend discovers the
                    // caller's installations from the code instead of trusting a supplied id.
                    installationId?: string
                    code: string
                    state: string
                }) => {
                    const body: StamphogSyncInstallationRequestApi = { code, state }
                    if (installationId) {
                        body.installation_id = installationId
                    }
                    return stamphogRepoConfigsSyncInstallationCreate(String(values.currentProjectId), body)
                },
            },
        ],
    })),

    reducers({
        // Repos with an in-flight PATCH — used to disable their switches so a
        // second toggle can't fire before the first resolves.
        updatingRepoIds: [
            [] as string[],
            {
                updateRepoConfig: (state, { id }) => (state.includes(id) ? state : [...state, id]),
                repoUpdateDone: (state, { id }) => state.filter((x) => x !== id),
            },
        ],
        repoConfigs: {
            repoConfigUpdated: (state, { config }) => state.map((repo) => (repo.id === config.id ? config : repo)),
            // Adding a paused repository turns its existing row back on, so replace before inserting.
            addRepositorySuccess: (state, { config }) =>
                sortByRepository([...state.filter((repo) => repo.id !== config.id), config]),
        },
        // An added repository opens by itself, so a search that hides it has to go.
        repoSearch: ['', { setRepoSearch: (_, { search }) => search, addRepositorySuccess: () => '' }],
        // A failed first load leaves the list empty, which must not read as "no repositories yet".
        repoConfigsFailed: [
            false,
            {
                loadRepoConfigs: () => false,
                loadRepoConfigsSuccess: () => false,
                loadRepoConfigsFailure: () => true,
            },
        ],
        availableRepositoriesFailed: [
            false,
            {
                loadAvailableRepositories: () => false,
                loadAvailableRepositoriesSuccess: () => false,
                loadAvailableRepositoriesFailure: () => true,
            },
        ],
        addedRepoIds: [
            [] as string[],
            {
                addRepositorySuccess: (state, { config }) => [...state.filter((x) => x !== config.id), config.id],
            },
        ],
        availableSearch: ['', { setAvailableSearch: (_, { search }) => search }],
        expandedRepoIds: [
            [] as string[],
            {
                setRepoExpanded: (state, { id, expanded }) =>
                    expanded ? [...state.filter((x) => x !== id), id] : state.filter((x) => x !== id),
                addRepositorySuccess: (state, { config }) => [...state.filter((x) => x !== config.id), config.id],
            },
        ],
        // Only an unfiltered answer counts every addable repository, so a search result leaves it alone.
        addableCount: [
            null as number | null,
            {
                loadAvailableRepositoriesSuccess: (state, { availableRepositories, payload }) =>
                    payload?.search.trim() ? state : availableRepositories.total_count,
            },
        ],
        repositoryToAdd: [
            null as string | null,
            {
                setRepositoryToAdd: (_, { repository }) => repository,
                // A new search replaces the options, so a pick from the old results must not stay armed.
                setAvailableSearch: (state, { search }) => (search.trim() ? null : state),
                addRepositorySuccess: () => null,
            },
        ],
        addingRepository: [
            false,
            {
                addRepository: () => true,
                addRepositorySuccess: () => false,
                addRepositoryFailure: () => false,
            },
        ],
        // The browser leaves for GitHub on success, so only a failure needs to reset these.
        openingInstallPage: [
            false,
            {
                openInstallPage: () => true,
                openInstallPageFailed: () => false,
            },
        ],
        refreshingFromGitHub: [
            false,
            {
                refreshFromGitHub: () => true,
                refreshFromGitHubFailed: () => false,
            },
        ],
    }),

    selectors({
        installUrl: [
            (s) => [s.installInfo],
            (installInfo: StamphogInstallInfoApi | null): string => installInfo?.install_url ?? '',
        ],
        appNotInstalled: [
            (s) => [s.syncResult],
            (syncResult: StamphogSyncInstallationResponseApi | null): boolean => syncResult?.app_not_installed ?? false,
        ],
        // Non-empty only when discovery found several installations and bound nothing: the user must
        // pick which one this team connects (reachability is not intent).
        discoveredInstallations: [
            (s) => [s.syncResult],
            (syncResult: StamphogSyncInstallationResponseApi | null): readonly StamphogDiscoveredInstallationApi[] =>
                syncResult?.installations ?? [],
        ],
        skippedRepos: [
            (s) => [s.syncResult],
            (syncResult: StamphogSyncInstallationResponseApi | null): readonly string[] => syncResult?.skipped ?? [],
        ],
        hasInstallation: [
            (s) => [s.availableRepositories],
            (availableRepositories: StamphogAvailableRepositoriesApi | null): boolean | null =>
                availableRepositories?.has_installation ?? null,
        ],
        // A failed search keeps the loader's previous answer, which belongs to another search.
        availableRepositoryOptions: [
            (s) => [s.availableRepositories, s.availableRepositoriesFailed],
            (
                availableRepositories: StamphogAvailableRepositoriesApi | null,
                availableRepositoriesFailed: boolean
            ): LemonInputSelectOption[] =>
                availableRepositoriesFailed
                    ? []
                    : (availableRepositories?.repositories ?? []).map((repository) => ({
                          key: repository,
                          label: repository,
                      })),
        ],
        // Every row reports the same team-wide level, so the first one answers for the whole scene.
        // Undefined until a repository loads, which sends the access checks back to the app context.
        stamphogAccessLevel: [
            (s) => [s.repoConfigs],
            (repoConfigs: StamphogRepoConfigApi[]): AccessControlLevel | undefined =>
                repoConfigs.length > 0 ? toAccessControlLevel(repoConfigs[0].user_access_level) : undefined,
        ],
        // Connecting, granting access, and refreshing all record the member's repositories for the team.
        // The flow finishes through the authorize URL, so an install link alone cannot connect anything.
        connectDisabledReason: [
            (s) => [s.installInfo, s.installInfoLoading, s.stamphogAccessLevel],
            (
                installInfo: StamphogInstallInfoApi | null,
                installInfoLoading: boolean,
                stamphogAccessLevel: AccessControlLevel | undefined
            ): string | null => {
                const accessReason = editorDisabledReason(stamphogAccessLevel)
                if (accessReason) {
                    return accessReason
                }
                if (installInfoLoading) {
                    return 'Loading install details'
                }
                if (!installInfo?.install_url || !installInfo.authorize_url) {
                    return 'The Stamphog GitHub App is not configured yet'
                }
                return null
            },
        ],
        filteredRepoConfigs: [
            (s) => [s.repoConfigs, s.repoSearch],
            (repoConfigs: StamphogRepoConfigApi[], repoSearch: string): StamphogRepoConfigApi[] => {
                const needle = repoSearch.trim().toLowerCase()
                return needle
                    ? repoConfigs.filter((repo) => repo.repository.toLowerCase().includes(needle))
                    : repoConfigs
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        updateRepoConfig: async ({ id, patch }) => {
            try {
                actions.repoConfigUpdated(
                    await stamphogRepoConfigsPartialUpdate(String(values.currentProjectId), id, patch)
                )
            } catch {
                lemonToast.error('Failed to update repository')
            } finally {
                actions.repoUpdateDone(id)
            }
        },
        setAvailableSearch: async ({ search }, breakpoint) => {
            await breakpoint(AVAILABLE_SEARCH_DEBOUNCE_MS)
            actions.loadAvailableRepositories({ search })
        },
        addRepository: async () => {
            const repository = values.repositoryToAdd
            if (!repository) {
                actions.addRepositoryFailure()
                return
            }
            try {
                const config = await stamphogRepoConfigsAddRepositoryCreate(String(values.currentProjectId), {
                    repository,
                })
                actions.addRepositorySuccess(config)
                lemonToast.success(`Stamphog now reviews ${config.repository}`)
            } catch (error: any) {
                lemonToast.error(error?.detail || 'Could not add the repository. Try again.')
                actions.addRepositoryFailure()
            }
        },
        addRepositorySuccess: () => {
            actions.loadRepoConfigs()
            actions.loadAvailableRepositories({ search: '' })
        },
        connectInstallation: async ({ installationId }) => {
            sessionStorage.setItem(PENDING_INSTALLATION_STORAGE_KEY, installationId)
            // The setup_action=update redirect carries no code (nothing to sync), so bounce the browser
            // through the authorize URL for one silent hop. GitHub redirects straight back with a code, and
            // the stashed installation id goes with it.
            if (!(await redirectToGitHub(String(values.currentProjectId), 'authorize_url'))) {
                sessionStorage.removeItem(PENDING_INSTALLATION_STORAGE_KEY)
            }
        },
        openInstallPage: async () => {
            if (!(await redirectToGitHub(String(values.currentProjectId), 'install_url'))) {
                actions.openInstallPageFailed()
            }
        },
        refreshFromGitHub: async () => {
            // A refresh picks no installation. A pick left over from a failed connect would otherwise ride
            // this callback and bind that installation instead.
            sessionStorage.removeItem(PENDING_INSTALLATION_STORAGE_KEY)
            // An App that is already authorized sends the browser straight back with a code, and the sync
            // re-lists the repositories this member can reach with their own GitHub token.
            if (!(await redirectToGitHub(String(values.currentProjectId), 'authorize_url'))) {
                actions.refreshFromGitHubFailed()
            }
        },
        syncInstallationSuccess: ({ syncResult }) => {
            // Drop the callback params from the URL so a refresh doesn't re-sync,
            // then reload both lists, because a sync can change what is available to add.
            router.actions.replace(urls.stamphog())
            if (syncResult?.app_not_installed) {
                // Discovery found no installation the user can reach — they still need to install the App.
                // The banner and connect button surface the install link.
                lemonToast.info("Stamphog isn't installed on GitHub yet. Use the install link to add it.")
            }
            actions.loadRepoConfigs()
            actions.loadAvailableRepositories({ search: '' })
        },
        syncInstallationFailure: () => {
            lemonToast.error('Could not connect the GitHub App installation')
        },
    })),

    urlToAction(({ actions }) => ({
        [urls.stamphogCallback()]: (_, searchParams) => {
            // Two redirects land here, both carrying the state token we minted in install_info:
            //   - authorize/fresh-install: a user OAuth code (+ installation_id on a fresh install). The
            //     backend proves ownership from the code and discovers or verifies the installation.
            //   - setup_action=update (app already installed): installation_id + state but NO code. The id
            //     is user-editable and not trusted, so restart via authorize to obtain a real code.
            // GitHub sends the user back with ?error=access_denied when they hit Cancel on the
            // authorize screen — a normal action on the primary connect flow, not a failure. Land
            // them back on the plain page instead of a silent dead-end on the callback URL.
            // Read and clear the stashed pick before any early return, so a stale id cannot bind the wrong
            // installation on a later code-only callback.
            const stashedInstallationId = sessionStorage.getItem(PENDING_INSTALLATION_STORAGE_KEY)
            sessionStorage.removeItem(PENDING_INSTALLATION_STORAGE_KEY)
            if (searchParams.error) {
                router.actions.replace(urls.stamphog())
                if (searchParams.error === 'access_denied') {
                    lemonToast.info('GitHub authorization was cancelled.')
                } else {
                    lemonToast.error('GitHub authorization failed. Try again.')
                }
                return
            }
            // A member without admin rights on the GitHub organization only files an install request, so
            // GitHub returns without an installation or a code. Nothing can connect until an owner approves.
            if (searchParams.setup_action === 'request') {
                router.actions.replace(urls.stamphog())
                lemonToast.info(
                    'GitHub sent your install request to the organization owners. Connect again once they approve it.'
                )
                return
            }
            // A stashed pick fills in for the missing installation_id on the authorize redirect; an explicit
            // URL param wins.
            const installationId = searchParams.installation_id || stashedInstallationId || undefined
            const code = searchParams.code
            const state = searchParams.state
            if (code && state) {
                actions.syncInstallation({
                    installationId: installationId ? String(installationId) : undefined,
                    code: String(code),
                    state: String(state),
                })
            } else if (installationId && state) {
                actions.connectInstallation(String(installationId))
            } else {
                // Backing out of GitHub's install page returns only the state, so there is nothing to connect.
                router.actions.replace(urls.stamphog())
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadRepoConfigs()
        actions.loadInstallInfo()
        actions.loadAvailableRepositories({ search: '' })
    }),
])
