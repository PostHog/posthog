export type stamphogDigestsSceneLogicType = MakeLogicType<
    stamphogDigestsSceneLogicValues,
    stamphogDigestsSceneLogicActions,
    Record<string, any>,
    stamphogDigestsSceneLogicMeta
>

export const stamphogDigestsSceneLogic = kea<stamphogDigestsSceneLogicType>([
    path(['products', 'stamphog', 'frontend', 'scenes', 'StamphogDigestsScene', 'stamphogDigestsSceneLogic']),

    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),

    actions({
        // Declared explicitly rather than left to the loaders builder: the loader takes a breakpoint,
        // so typegen would otherwise infer a required payload from its first parameter and every
        // `loadDigestRuns()` call site would stop compiling.
        loadDigestRuns: true,
        setPage: (page: number) => ({ page }),
        digestRunExpanded: (run: DigestRunApi) => ({ run }),
        slackMessageLinkClicked: (run: DigestRunApi) => ({ run }),
        digestPrLinkClicked: (run: DigestRunApi) => ({ run }),
    }),

    reducers({
        page: [1, { setPage: (_, { page }) => page }],
        // A failed request resolves the loader with a null response, which the runs selector turns into
        // an empty list. Without this the table would claim there are no digests when it simply could
        // not ask. Loading, empty and error are three different screens.
        digestRunsFailed: [
            false,
            {
                loadDigestRuns: () => false,
                loadDigestRunsSuccess: () => false,
                loadDigestRunsFailure: () => true,
            },
        ],
    }),

    loaders(({ values }) => ({
        digestRunsResponse: [
            null as PaginatedDigestRunListApi | null,
            {
                loadDigestRuns: async (_, breakpoint) => {
                    // urlToAction replays on mount, so a deep link sets the page through its own
                    // listener. Debounce so only the settled page loads.
                    await breakpoint(1)
                    return stamphogDigestRunsList(String(values.currentProjectId), {
                        limit: DIGESTS_PAGE_SIZE,
                        offset: (values.page - 1) * DIGESTS_PAGE_SIZE,
                    })
                },
            },
        ],
    })),

    selectors({
        digestRuns: [
            (s) => [s.digestRunsResponse],
            (digestRunsResponse: PaginatedDigestRunListApi | null): DigestRunApi[] => digestRunsResponse?.results ?? [],
        ],
        digestRunsCount: [
            (s) => [s.digestRunsResponse],
            (digestRunsResponse: PaginatedDigestRunListApi | null): number => digestRunsResponse?.count ?? 0,
        ],
    }),

    listeners(({ actions }) => ({
        setPage: () => actions.loadDigestRuns(),
        // The event names are frozen: insights on digest usage break if one is renamed.
        digestRunExpanded: ({ run }) => {
            posthog.capture('stamphog digest expanded', digestRunEventProperties(run))
        },
        slackMessageLinkClicked: ({ run }) => {
            posthog.capture('stamphog digest slack message opened', digestRunEventProperties(run))
        },
        digestPrLinkClicked: ({ run }) => {
            posthog.capture('stamphog digest pull request opened', digestRunEventProperties(run))
        },
    })),

    actionToUrl(({ values }) => {
        const toUrl = (): [string, Record<string, string>] => [
            urls.stamphogDigests(),
            values.page > 1 ? { page: String(values.page) } : {},
        ]
        return { setPage: toUrl }
    }),

    urlToAction(({ actions, values }) => ({
        [urls.stamphogDigests()]: (_: any, searchParams: Record<string, any>) => {
            const page = Number(searchParams.page ?? 1) || 1
            // Guarded against the current value so replaying an unchanged page on mount does not
            // fire a second load.
            if (page !== values.page) {
                actions.setPage(page)
            }
        },
    })),

    afterMount(({ actions }) => {
        posthog.capture('stamphog digests viewed')
        actions.loadDigestRuns()
    }),
])
