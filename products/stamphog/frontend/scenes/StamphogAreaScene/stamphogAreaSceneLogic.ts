export const stamphogAreaSceneLogic = kea<stamphogAreaSceneLogicType>([
    path(['products', 'stamphog', 'frontend', 'scenes', 'StamphogAreaScene', 'stamphogAreaSceneLogic']),

    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),

    actions({
        // Declared explicitly because the loaders take a breakpoint, so typegen would otherwise infer a
        // required payload.
        loadRuns: true,
        loadOwners: true,
        setOwner: (owner: string) => ({ owner }),
        setFilter: (filter: AreaFilter) => ({ filter }),
        setWindowDays: (windowDays: AreaWindowDays) => ({ windowDays }),
        // Applies a whole link at once, so opening a link is one change instead of one per filter.
        setFilters: (filters: AreaFilterValues) => ({ filters }),
    }),

    reducers({
        // Persisted per viewer, because most people look at the same team every time. kea-localstorage
        // catches storage errors, so a blocked localStorage only loses the remembered value.
        owner: [
            '',
            { persist: true },
            { setOwner: (_, { owner }) => owner.trim(), setFilters: (_, { filters }) => filters.owner.trim() },
        ],
        filter: [
            DEFAULT_AREA_FILTER as AreaFilter,
            { setFilter: (_, { filter }) => filter, setFilters: (_, { filters }) => filters.filter },
        ],
        windowDays: [
            DEFAULT_WINDOW_DAYS as AreaWindowDays,
            { setWindowDays: (_, { windowDays }) => windowDays, setFilters: (_, { filters }) => filters.windowDays },
        ],
        // A failed request leaves the loader at null, which reads the same as "no team yet". The flag
        // keeps the error screen apart from the empty and the loading screens.
        runsFailed: [
            false,
            {
                loadRuns: () => false,
                loadRunsSuccess: () => false,
                loadRunsFailure: () => true,
            },
        ],
    }),

    loaders(({ values }) => ({
        runsResponse: [
            null as PaginatedStamphogRoutingRunListApi | null,
            {
                loadRuns: async (_, breakpoint) => {
                    // A newer load supersedes this one, so a deep link that fires several actions makes one request.
                    await breakpoint(1)
                    if (!values.owner) {
                        return null
                    }
                    const params: StamphogRoutingRunsListParams = {
                        owner: values.owner,
                        outcome: AREA_FILTER_OUTCOMES[values.filter],
                        latest_per_pr: true,
                        merged_after: dayjs().subtract(values.windowDays, 'day').toISOString(),
                        ordering: StamphogRoutingRunsListOrdering.MergedAt,
                        limit: AREA_PAGE_SIZE,
                    }
                    const response = await stamphogRoutingRunsList(String(values.currentProjectId), params)
                    // A filter change while this request ran started a newer load, so drop this response.
                    breakpoint()
                    return response
                },
            },
        ],
        owners: [
            [] as StamphogRoutingOwnerCountApi[],
            {
                loadOwners: async () => stamphogRoutingRunsOwnersList(String(values.currentProjectId)),
            },
        ],
        runDetails: [
            {} as Record<string, StamphogRoutingRunDetailApi>,
            {
                loadRunDetail: async (id: string) => {
                    if (values.runDetails[id]) {
                        return values.runDetails
                    }
                    const detail = await stamphogRoutingRunsRetrieve(String(values.currentProjectId), id)
                    // Read the map again after the request, so two rows opened together both keep their files.
                    return { ...values.runDetails, [id]: detail }
                },
            },
        ],
    })),

    selectors({
        runs: [
            (s) => [s.runsResponse],
            (runsResponse: PaginatedStamphogRoutingRunListApi | null): StamphogRoutingRunApi[] =>
                runsResponse?.results ?? [],
        ],
        groups: [
            (s) => [s.runs, s.owner],
            (runs: StamphogRoutingRunApi[], owner: string): AreaGroupRows[] => groupAreaRows(runs, owner),
        ],
        headline: [
            (s) => [s.runs, s.owner],
            (runs: StamphogRoutingRunApi[], owner: string): AreaHeadline => {
                const decisions = runs.flatMap((run) => ownerDecision(run, owner) ?? [])
                return {
                    changed: decisions.length,
                    mergedWithoutTeam: decisions.filter((decision) => isMergedWithoutTeam(decision.outcome)).length,
                    sensitive: decisions.filter(touchesSensitivePath).length,
                }
            },
        ],
        showsOnlyNewest: [
            (s) => [s.runsResponse],
            (runsResponse: PaginatedStamphogRoutingRunListApi | null): boolean => !!runsResponse?.next,
        ],
    }),

    listeners(({ actions }) => ({
        setOwner: () => actions.loadRuns(),
        setFilter: () => actions.loadRuns(),
        setWindowDays: () => actions.loadRuns(),
        setFilters: () => actions.loadRuns(),
    })),

    actionToUrl(({ values }) => {
        const toUrl = (): [string, Record<string, string>] => [
            urls.stamphogArea(),
            {
                ...(values.owner ? { team: values.owner } : {}),
                ...(values.filter !== DEFAULT_AREA_FILTER ? { show: values.filter } : {}),
                days: String(values.windowDays),
            },
        ]
        return {
            setOwner: toUrl,
            setFilter: toUrl,
            setWindowDays: toUrl,
        }
    }),

    urlToAction(({ actions, values }) => ({
        [urls.stamphogArea()]: (_: any, searchParams: Record<string, any>) => {
            // A link without a team keeps the team this viewer looked at last.
            const owner = typeof searchParams.team === 'string' ? searchParams.team : values.owner
            const filter =
                AREA_FILTER_OPTIONS.find((option) => option.value === searchParams.show)?.value ?? DEFAULT_AREA_FILTER
            const windowDays =
                AREA_WINDOW_OPTIONS.find((option) => option.value === Number(searchParams.days))?.value ??
                DEFAULT_WINDOW_DAYS
            // The URL echoes every change the controls make, so skip it when nothing differs.
            if (owner === values.owner && filter === values.filter && windowDays === values.windowDays) {
                return
            }
            actions.setFilters({ owner, filter, windowDays })
        },
    })),

    afterMount(({ actions }) => {
        actions.loadOwners()
        actions.loadRuns()
    }),
])
