export const stamphogTeamViewSceneLogic = kea<stamphogTeamViewSceneLogicType>([
    path(['products', 'stamphog', 'frontend', 'scenes', 'StamphogTeamViewScene', 'stamphogTeamViewSceneLogic']),

    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),

    actions({
        // Declared explicitly for the same reason as in the runs scene: the loader takes a breakpoint, so
        // typegen would otherwise infer a required payload for loadRuns.
        loadRuns: true,
        setOwner: (owner: string) => ({ owner }),
        setOutcome: (outcome: TeamViewOutcome) => ({ outcome }),
        setWindowDays: (windowDays: TeamViewWindowDays) => ({ windowDays }),
        setMerged: (merged: boolean) => ({ merged }),
        setPage: (page: number) => ({ page }),
        // Applies a whole link at once, so opening a link is one change instead of one per filter.
        setFilters: (filters: TeamViewFilterValues) => ({ filters }),
    }),

    reducers({
        // Persisted per viewer, because most people look at the same team every time. kea-localstorage
        // catches storage errors, so a blocked localStorage only loses the remembered value.
        owner: [
            '',
            { persist: true },
            { setOwner: (_, { owner }) => owner.trim(), setFilters: (_, { filters }) => filters.owner.trim() },
        ],
        outcome: [
            DEFAULT_OUTCOME,
            { setOutcome: (_, { outcome }) => outcome, setFilters: (_, { filters }) => filters.outcome },
        ],
        windowDays: [
            DEFAULT_WINDOW_DAYS,
            { setWindowDays: (_, { windowDays }) => windowDays, setFilters: (_, { filters }) => filters.windowDays },
        ],
        merged: [true, { setMerged: (_, { merged }) => merged, setFilters: (_, { filters }) => filters.merged }],
        page: [
            1,
            {
                setPage: (_, { page }) => page,
                setFilters: (_, { filters }) => filters.page,
                setOwner: () => 1,
                setOutcome: () => 1,
                setWindowDays: () => 1,
                setMerged: () => 1,
            },
        ],
        // A failed request leaves the loader at null, which reads the same as "no team yet". The flag
        // keeps the error screen apart from the empty and the loading screens.
        runsFailed: [
            false,
            {
                loadRuns: () => false,
                loadRunsSuccess: () => false,
                loadRunsFailure: () => true,
            },
        ],
    }),

    loaders(({ values }) => ({
        runsResponse: [
            null as PaginatedStamphogRoutingRunListApi | null,
            {
                loadRuns: async (_, breakpoint) => {
                    // A newer load supersedes this one, so a deep link that fires several actions makes one request.
                    await breakpoint(1)
                    if (!values.owner) {
                        return null
                    }
                    const since = dayjs().subtract(values.windowDays, 'day').toISOString()
                    const params: StamphogRoutingRunsListParams = {
                        owner: values.owner,
                        outcome:
                            values.outcome === StamphogRoutingRunsListOutcomeItem.Requested
                                ? ASKED_OUTCOMES
                                : [values.outcome],
                        latest_per_pr: true,
                        limit: TEAM_VIEW_PAGE_SIZE,
                        offset: (values.page - 1) * TEAM_VIEW_PAGE_SIZE,
                        // An open pull request has no merge time, so the window and the order use the run time.
                        ...(values.merged
                            ? { merged: true, merged_after: since, ordering: StamphogRoutingRunsListOrdering.MergedAt }
                            : { merged: false, created_after: since }),
                    }
                    return stamphogRoutingRunsList(String(values.currentProjectId), params)
                },
            },
        ],
    })),

    selectors({
        runs: [
            (s) => [s.runsResponse],
            (runsResponse: PaginatedStamphogRoutingRunListApi | null): StamphogRoutingRunApi[] =>
                runsResponse?.results ?? [],
        ],
    }),

    listeners(({ actions }) => ({
        // The team field sets the owner on every keystroke, so wait until typing pauses. The other
        // filters change in one step and load right away.
        setOwner: async (_, breakpoint) => {
            await breakpoint(300)
            actions.loadRuns()
        },
        setOutcome: () => actions.loadRuns(),
        setWindowDays: () => actions.loadRuns(),
        setMerged: () => actions.loadRuns(),
        setPage: () => actions.loadRuns(),
        setFilters: () => actions.loadRuns(),
    })),

    actionToUrl(({ values }) => {
        const toUrl = (): [string, Record<string, string>] => [
            urls.stamphogTeamView(),
            {
                ...(values.owner ? { team: values.owner } : {}),
                outcome: values.outcome,
                days: String(values.windowDays),
                ...(values.merged ? {} : { merged: 'false' }),
                ...(values.page > 1 ? { page: String(values.page) } : {}),
            },
        ]
        return {
            setOwner: toUrl,
            setOutcome: toUrl,
            setWindowDays: toUrl,
            setMerged: toUrl,
            setPage: toUrl,
        }
    }),

    urlToAction(({ actions, values }) => ({
        [urls.stamphogTeamView()]: (_: any, searchParams: Record<string, any>) => {
            // A link without a team keeps the team this viewer looked at last.
            const owner = typeof searchParams.team === 'string' ? searchParams.team : values.owner
            const outcome =
                TEAM_VIEW_OUTCOME_OPTIONS.find((option) => option.value === searchParams.outcome)?.value ??
                DEFAULT_OUTCOME
            const windowDays =
                TEAM_VIEW_WINDOW_OPTIONS.find((option) => option.value === Number(searchParams.days))?.value ??
                DEFAULT_WINDOW_DAYS
            const merged = searchParams.merged !== 'false' && searchParams.merged !== false
            const page = Number(searchParams.page ?? 1) || 1
            // The URL echoes every change the controls make, so skip it when nothing differs.
            const unchanged =
                owner === values.owner &&
                outcome === values.outcome &&
                windowDays === values.windowDays &&
                merged === values.merged &&
                page === values.page
            if (unchanged) {
                return
            }
            actions.setFilters({ owner, outcome, windowDays, merged, page })
        },
    })),

    afterMount(({ actions }) => {
        actions.loadRuns()
    }),
])
