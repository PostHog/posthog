import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { actionToUrl, urlToAction } from 'kea-router'

import { dayjs } from 'lib/dayjs'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { stamphogRoutingRunsList } from '../../generated/api'
import {
    type PaginatedStamphogRoutingRunListApi,
    type StamphogRoutingRunApi,
    StamphogRoutingRunsListOrdering,
    StamphogRoutingRunsListOutcomeItem,
    type StamphogRoutingRunsListParams,
} from '../../generated/api.schemas'
import {
    ASKED_OUTCOMES,
    DEFAULT_OUTCOME,
    DEFAULT_WINDOW_DAYS,
    TEAM_VIEW_OUTCOME_OPTIONS,
    TEAM_VIEW_WINDOW_OPTIONS,
    TeamViewOutcome,
    TeamViewWindowDays,
} from './routingRunDisplay'

export const TEAM_VIEW_PAGE_SIZE = 50

export interface TeamViewFilterValues {
    owner: string
    outcome: TeamViewOutcome
    windowDays: TeamViewWindowDays
    merged: boolean
    page: number
}

