// Shared with the legacy prompt on purpose: one cooldown per browser, whichever runtime showed it.
const LAST_SHOWN_STORAGE_KEY = 'posthog_ai_feedback_last_shown'

export interface FeedbackPromptLogicProps {
    /** Conversation id where one exists, else the task id. Lands in `$ai_session_id`. */
    sessionId: string
    /** Key of the live `runStreamLogic` instance this prompt observes. */
    streamKey: string
}

/** What the capture needs from the stream at the moment of rating. */
interface StreamSnapshot {
    traceId: string | null
    turnIndex: number | null
    humanMessageCount: number
    run: RunRef | undefined
}

function readStream(streamKey: string): StreamSnapshot {
    const stream = runStreamLogic.findMounted({ streamKey })
    if (!stream) {
        return { traceId: null, turnIndex: null, humanMessageCount: 0, run: undefined }
    }
    const items = stream.values.threadItems
    const trailers = computeTurnTrailers(items)
    const lastTurn = [...trailers.values()].find((trailer) => trailer.isLastTurn)
    return {
        traceId: stream.values.traceId,
        turnIndex: lastTurn?.turnIndex ?? null,
        humanMessageCount: items.filter((item) => item.type === 'human_message').length,
        run: stream.cache.activeRun as RunRef | undefined,
    }
}

