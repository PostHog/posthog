/**
 * The periodic "how is PostHog AI doing?" prompt for the sandbox runtime. Same trigger rules and flag
 * config as the legacy Max prompt: every Nth human message, a random sample, or a run of
 * cancelled turns, throttled by a per-browser cooldown. The retry trigger has no sandbox equivalent.
 */
export const feedbackPromptLogic = kea<feedbackPromptLogicType>([
    path(['products', 'posthog_ai', 'frontend', 'logics', 'feedbackPromptLogic']),
    props({} as FeedbackPromptLogicProps),
    key((props) => props.sessionId),

    connect((props: FeedbackPromptLogicProps) => ({
        actions: [runStreamLogic({ streamKey: props.streamKey }), ['cancelRun']],
    })),

    actions({
        submitRating: (rating: FeedbackPromptRating) => ({ rating }),
        submitDetailedFeedback: (feedbackText?: string) => ({ feedbackText }),
        completeDetailedFeedback: true,
        checkShouldShowPrompt: (messageCount: number) => ({ messageCount }),
        showPrompt: (triggerType: FeedbackPromptTrigger) => ({ triggerType }),
        hidePrompt: true,
        showDetailedFeedback: true,
        hideDetailedFeedback: true,
        showThankYou: true,
        hideThankYou: true,
        implicitDismissPrompt: true,
        implicitDismissDetailedFeedback: true,
        recordFeedbackShown: true,
        setLastTriggeredIntervalIndex: (index: number) => ({ index }),
    }),

    reducers({
        isPromptVisible: [
            false,
            {
                showPrompt: () => true,
                hidePrompt: () => false,
                implicitDismissPrompt: () => false,
                showDetailedFeedback: () => false,
                showThankYou: () => false,
            },
        ],
        isDetailedFeedbackVisible: [
            false,
            {
                showDetailedFeedback: () => true,
                hideDetailedFeedback: () => false,
                implicitDismissDetailedFeedback: () => false,
                hidePrompt: () => false,
            },
        ],
        isThankYouVisible: [
            false,
            {
                showThankYou: () => true,
                hideThankYou: () => false,
                showPrompt: () => false,
            },
        ],
        currentTriggerType: [
            'manual' as FeedbackPromptTrigger,
            {
                showPrompt: (_, { triggerType }) => triggerType,
                hidePrompt: () => 'manual' as FeedbackPromptTrigger,
            },
        ],
        lastTriggeredIntervalIndex: [
            0,
            {
                setLastTriggeredIntervalIndex: (_, { index }) => index,
            },
        ],
        // Cancelled turns in this session since the prompt was last answered.
        cancelCount: [
            0,
            {
                cancelRun: (state) => state + 1,
                submitRating: () => 0,
                completeDetailedFeedback: () => 0,
            },
        ],
    }),

    selectors({
        feedbackConfig: [
            () => [],
            (): FeedbackPromptConfig | null => {
                const payload = getFeatureFlagPayload(FEATURE_FLAGS.POSTHOG_AI_CONVERSATION_FEEDBACK_CONFIG)
                if (!payload || typeof payload !== 'object') {
                    posthog.captureException(
                        new Error('POSTHOG_AI_CONVERSATION_FEEDBACK_CONFIG feature flag is not set'),
                        { tags: { product: 'max_ai' } }
                    )
                    return null
                }
                return {
                    cooldownMs: payload.cooldownMs,
                    messageInterval: payload.messageInterval,
                    samplingRate: payload.samplingRate,
                    cancelThreshold: payload.cancelThreshold,
                }
            },
        ],
        canShowPrompt: [
            (s) => [s.feedbackConfig],
            (feedbackConfig: FeedbackPromptConfig | null): boolean => {
                if (!feedbackConfig) {
                    return false
                }
                const lastShown = localStorage.getItem(LAST_SHOWN_STORAGE_KEY)
                if (!lastShown) {
                    return true
                }
                return Date.now() - parseInt(lastShown, 10) > feedbackConfig.cooldownMs
            },
        ],
        messageInterval: [
            (s) => [s.feedbackConfig],
            (feedbackConfig: FeedbackPromptConfig | null): number => feedbackConfig?.messageInterval ?? 10,
        ],
    }),

    listeners(({ actions, values, props, cache }) => ({
        submitRating: ({ rating }) => {
            const { currentTriggerType, messageInterval } = values
            const stream = readStream(props.streamKey)

            // "bad" opens the detailed form; the capture happens on submit.
            if (rating === 'bad') {
                actions.showDetailedFeedback()
                return
            }

            capturePromptFeedback(
                props.sessionId,
                stream.traceId,
                rating,
                currentTriggerType,
                stream.turnIndex,
                stream.run
            )
            actions.recordFeedbackShown()

            // Pin the interval index so the same message count cannot re-trigger the prompt.
            actions.setLastTriggeredIntervalIndex(Math.floor(stream.humanMessageCount / messageInterval))

            if (rating === 'dismissed') {
                actions.hidePrompt()
            } else {
                actions.showThankYou()
                cache.disposables.add((): (() => void) => {
                    const timer = window.setTimeout(() => actions.hideThankYou(), 2000)
                    return () => clearTimeout(timer)
                }, 'hide-thank-you')
            }
        },

        submitDetailedFeedback: ({ feedbackText }) => {
            const stream = readStream(props.streamKey)
            capturePromptFeedback(
                props.sessionId,
                stream.traceId,
                'bad',
                values.currentTriggerType,
                stream.turnIndex,
                stream.run,
                feedbackText
            )
            actions.recordFeedbackShown()
        },

        checkShouldShowPrompt: ({ messageCount }) => {
            const { feedbackConfig } = values
            if (!feedbackConfig || values.isPromptVisible) {
                return
            }

            // Read the cooldown directly: the selector is not reactive to localStorage.
            const lastShown = localStorage.getItem(LAST_SHOWN_STORAGE_KEY)
            if (lastShown && Date.now() - parseInt(lastShown, 10) < feedbackConfig.cooldownMs) {
                return
            }

            if (values.cancelCount >= feedbackConfig.cancelThreshold) {
                actions.showPrompt('cancel')
                return
            }

            if (messageCount > 0 && messageCount % feedbackConfig.messageInterval === 0) {
                const currentIntervalIndex = Math.floor(messageCount / feedbackConfig.messageInterval)
                if (currentIntervalIndex > values.lastTriggeredIntervalIndex) {
                    actions.setLastTriggeredIntervalIndex(currentIntervalIndex)
                    actions.showPrompt('message_interval')
                    return
                }
            }

            if (Math.random() < feedbackConfig.samplingRate) {
                actions.showPrompt('random_sample')
            }
        },

        recordFeedbackShown: () => {
            localStorage.setItem(LAST_SHOWN_STORAGE_KEY, Date.now().toString())
        },

        implicitDismissPrompt: () => {
            const stream = readStream(props.streamKey)
            capturePromptFeedback(
                props.sessionId,
                stream.traceId,
                'implicit_dismiss',
                values.currentTriggerType,
                stream.turnIndex,
                stream.run
            )
            actions.recordFeedbackShown()
        },

        implicitDismissDetailedFeedback: () => {
            const stream = readStream(props.streamKey)
            capturePromptFeedback(
                props.sessionId,
                stream.traceId,
                'bad',
                values.currentTriggerType,
                stream.turnIndex,
                stream.run
            )
            actions.recordFeedbackShown()
        },

        completeDetailedFeedback: () => {
            const stream = readStream(props.streamKey)
            actions.setLastTriggeredIntervalIndex(Math.floor(stream.humanMessageCount / values.messageInterval))
            actions.hideDetailedFeedback()
        },
    })),
])
