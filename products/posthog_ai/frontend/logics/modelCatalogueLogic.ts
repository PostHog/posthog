import { MakeLogicType, connect, kea, path, selectors } from 'kea'

import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'

import {
    ModelChoiceApi,
    ReasoningEffortEnumApi,
    RuntimeAdapterEnumApi,
} from 'products/tasks/frontend/generated/api.schemas'
import { MODELS } from 'products/tasks/frontend/modelCatalog.generated'

// The catalog and these enums are generated from the same Python definitions, so the casts
// restate what codegen already guarantees.
const CATALOGUE: ModelChoiceApi[] = MODELS.map((model) => ({
    runtime_adapter: model.runtimeAdapter as RuntimeAdapterEnumApi,
    model: model.id,
    display_name: model.label,
    supported_efforts: [...model.reasoningEfforts] as ReasoningEffortEnumApi[],
}))

// The flag a model needs before the picker offers it, from the same catalog row. Display
// only: the run API rejects a model the person may not use, whatever the picker showed.
const ACCESS_FLAG_BY_MODEL: Record<string, string> = Object.fromEntries(
    MODELS.filter((model) => model.accessFlag).map((model) => [model.id, model.accessFlag as string])
)

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface modelCatalogueLogicValues {
    featureFlags: FeatureFlagsSet; // featureFlagLogic
    catalogue: ModelChoiceApi[];
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface modelCatalogueLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        catalogue: (featureFlags: FeatureFlagsSet) => ModelChoiceApi[];
    };
}

export type modelCatalogueLogicType = MakeLogicType<modelCatalogueLogicValues, {}, Record<string, any>, modelCatalogueLogicMeta>;

/**
 * The models a task run may use, read from the generated model catalog.
 *
 * The catalog is the same definition the backend validates a run against, so the composer can only offer a selection
 * the API accepts. Baking it in rather than fetching it means the model dropdown is populated on first render, with no
 * request to wait on and nothing to fall back to when one fails. A model reaches the composer when the catalog is
 * regenerated, which is also what ships it to the backend and the desktop app.
 */
export const modelCatalogueLogic = kea<modelCatalogueLogicType>([
    path(['products', 'posthog_ai', 'frontend', 'logics', 'modelCatalogueLogic']),

    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),

    selectors({
        catalogue: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): ModelChoiceApi[] =>
                CATALOGUE.filter((choice) => {
                    const flag = ACCESS_FLAG_BY_MODEL[choice.model]
                    return !flag || !!featureFlags[flag]
                }),
        ],
    }),
])
