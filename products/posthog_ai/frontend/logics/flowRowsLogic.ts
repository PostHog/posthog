import { LogicWrapper, MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers } from 'kea'

import { FLOW_INITIAL_ROWS, type FlowWindow, fillFlowWindow } from '../utils/flowWindow'

/** Time budget per fill step, under the 50 ms long-task line. */
const FLOW_CHUNK_BUDGET_MS = 40
const FLOW_MIN_CHUNK_ROWS = 4
const FLOW_MAX_CHUNK_ROWS = 256
/** The fill waits this long after the last input, so a scroll or a keystroke never waits for a fill step. */
const FLOW_INPUT_PAUSE_MS = 200
const FLOW_INPUT_EVENTS = ['wheel', 'touchmove', 'keydown', 'pointerdown', 'pointermove'] as const

export interface FlowRowsLogicProps {
    flowKey: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface flowRowsLogicValues {
    flowWindow: FlowWindow | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface flowRowsLogicActions {
    chunkCommitted: (committedAt: number) => {
        committedAt: number
    }
    fillChunk: (rows: number) => {
        rows: number
    }
    scheduleNextChunk: () => {
        value: true
    }
    syncWindow: (flowWindow: FlowWindow) => {
        flowWindow: FlowWindow
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface flowRowsLogicMeta {
    key: string
}

export type flowRowsLogicType = MakeLogicType<
    flowRowsLogicValues,
    flowRowsLogicActions,
    FlowRowsLogicProps,
    flowRowsLogicMeta
>

/**
 * The render window of one flow-mode thread. A long thread opens with only its newest rows, then
 * renders the older rows in small steps between frames, so the page never freezes on one huge commit.
 */
export const flowRowsLogic: LogicWrapper<flowRowsLogicType> = kea<flowRowsLogicType>([
    props({} as FlowRowsLogicProps),
    key((props) => props.flowKey),
    path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'flowRowsLogic', key]),
    actions({
        syncWindow: (flowWindow: FlowWindow) => ({ flowWindow }),
        fillChunk: (rows: number) => ({ rows }),
        chunkCommitted: (committedAt: number) => ({ committedAt }),
        scheduleNextChunk: true,
    }),
    reducers({
        flowWindow: [
            null as FlowWindow | null,
            {
                syncWindow: (_, { flowWindow }) => flowWindow,
                fillChunk: (state, { rows }) => (state ? fillFlowWindow(state, rows) : state),
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        syncWindow: () => {
            actions.scheduleNextChunk()
        },
        chunkCommitted: ({ committedAt }) => {
            if (cache.chunkStartedAt !== null) {
                const elapsed = Math.max(1, committedAt - cache.chunkStartedAt)
                cache.chunkStartedAt = null
                cache.chunkRows = Math.min(
                    FLOW_MAX_CHUNK_ROWS,
                    Math.max(FLOW_MIN_CHUNK_ROWS, Math.round((cache.chunkRows * FLOW_CHUNK_BUDGET_MS) / elapsed))
                )
            }
            actions.scheduleNextChunk()
        },
        scheduleNextChunk: () => {
            if (!values.flowWindow?.holes.length) {
                cache.disposables.dispose('nextChunk')
                return
            }
            cache.disposables.add(() => {
                let timer: ReturnType<typeof setTimeout>
                const renderNextChunk = (): void => {
                    const wait = FLOW_INPUT_PAUSE_MS - (performance.now() - cache.lastInputAt)
                    if (wait > 0) {
                        timer = setTimeout(renderNextChunk, wait)
                        return
                    }
                    cache.chunkStartedAt = performance.now()
                    actions.fillChunk(cache.chunkRows)
                }
                timer = setTimeout(renderNextChunk, 0)
                return () => clearTimeout(timer)
            }, 'nextChunk')
        },
    })),
    afterMount(({ cache }) => {
        cache.chunkRows = FLOW_INITIAL_ROWS
        cache.chunkStartedAt = null
        cache.lastInputAt = -Infinity
        cache.disposables.add(() => {
            const noteInput = (event: Event): void => {
                // A pointer that moves without a pressed button is a hover, not an interaction.
                if (event.type !== 'pointermove' || (event as PointerEvent).buttons !== 0) {
                    cache.lastInputAt = performance.now()
                }
            }
            for (const type of FLOW_INPUT_EVENTS) {
                window.addEventListener(type, noteInput, { capture: true, passive: true })
            }
            return () => {
                for (const type of FLOW_INPUT_EVENTS) {
                    window.removeEventListener(type, noteInput, { capture: true })
                }
            }
        })
    }),
])
