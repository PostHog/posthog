/**
 * Alerts the user when a task's agent finishes a turn while they are away from the tab: a sound (a
 * PostHog Desktop built-in or one they upload) and an optional browser notification. Preferences live in
 * localStorage, so they apply per browser. Listens to the live turn-complete events on the tool-stream
 * bus, which never carry history replays.
 */
export const taskTurnNotificationLogic = kea<taskTurnNotificationLogicType>([
    path(['products', 'posthog_ai', 'frontend', 'logics', 'taskTurnNotificationLogic']),
    connect(() => ({
        actions: [toolStreamEventsLogic, ['emitTurnCompleteEvent']],
    })),
    actions({
        setBrowserNotificationsEnabled: (enabled: boolean) => ({ enabled }),
        requestPermission: true,
        setPermission: (permission: NotificationPermission) => ({ permission }),
        setSound: (sound: TurnSound) => ({ sound }),
        setVolume: (volume: number) => ({ volume }),
        previewSound: true,
        uploadCustomSound: (file: File) => ({ file }),
        setCustomSound: (customSound: CustomTurnSound | null) => ({ customSound }),
        removeCustomSound: true,
    }),
    reducers({
        browserNotificationsEnabled: [
            false,
            { persist: true, storageKey: 'posthog_ai.turnNotifications.browser' },
            { setBrowserNotificationsEnabled: (_, { enabled }) => enabled },
        ],
        sound: [
            'none' as TurnSound,
            { persist: true, storageKey: 'posthog_ai.turnNotifications.sound' },
            {
                setSound: (_, { sound }) => sound,
                removeCustomSound: (state) => (state === 'custom' ? 'none' : state),
            },
        ],
        volume: [
            80,
            { persist: true, storageKey: 'posthog_ai.turnNotifications.volume' },
            { setVolume: (_, { volume }) => volume },
        ],
        customSound: [
            null as CustomTurnSound | null,
            { persist: true, storageKey: 'posthog_ai.turnNotifications.customSound' },
            {
                setCustomSound: (_, { customSound }) => customSound,
                removeCustomSound: () => null,
            },
        ],
        permission: [
            (isNotificationSupported() ? Notification.permission : 'denied') as NotificationPermission,
            { setPermission: (_, { permission }) => permission },
        ],
    }),
    selectors({
        isNotificationSupported: [() => [], (): boolean => isNotificationSupported()],
        isPermissionDenied: [
            (s) => [s.isNotificationSupported, s.permission],
            (supported: boolean, permission: NotificationPermission): boolean => supported && permission === 'denied',
        ],
    }),
    listeners(({ actions, values }) => ({
        emitTurnCompleteEvent: ({ event }) => {
            if (!isUserAway()) {
                return
            }
            const soundUrl = resolveTurnSoundUrl(values.sound, values.customSound)
            const showBrowserNotification =
                values.browserNotificationsEnabled && isNotificationSupported() && Notification.permission === 'granted'
            if (!soundUrl && !showBrowserNotification) {
                return
            }
            if (soundUrl) {
                playTurnSound(soundUrl, values.volume)
            }
            if (showBrowserNotification) {
                const taskId = event.taskId
                const taskTitle = taskId ? taskLogic.findMounted({ taskId })?.values.task?.title : undefined
                const notification = new Notification(taskTitle || 'PostHog AI', {
                    body: 'The agent finished its turn.',
                    icon: NOTIFICATION_ICON,
                    // One notification per stream: a newer turn replaces the older one.
                    tag: `posthog-ai-turn-${event.streamKey}`,
                    silent: !!soundUrl,
                })
                notification.onclick = () => {
                    window.focus()
                    if (taskId) {
                        router.actions.push(urls.taskDetail(taskId))
                    }
                    notification.close()
                    posthog.capture('posthog ai turn notification clicked')
                }
            }
            posthog.capture('posthog ai turn notification delivered', {
                sound: values.sound,
                browser_notification: showBrowserNotification,
            })
        },
        setBrowserNotificationsEnabled: ({ enabled }) => {
            posthog.capture('posthog ai turn notification settings changed', {
                setting: 'browser_notifications',
                value: enabled,
            })
            if (enabled && values.permission !== 'granted') {
                actions.requestPermission()
            }
        },
        requestPermission: async () => {
            if (!isNotificationSupported()) {
                actions.setBrowserNotificationsEnabled(false)
                return
            }
            let result: NotificationPermission
            try {
                result = await Notification.requestPermission()
            } catch {
                result = Notification.permission
            }
            actions.setPermission(result)
            if (result !== 'granted') {
                actions.setBrowserNotificationsEnabled(false)
            }
        },
        setSound: ({ sound }) => {
            posthog.capture('posthog ai turn notification settings changed', { setting: 'sound', value: sound })
            actions.previewSound()
        },
        previewSound: () => {
            const url = resolveTurnSoundUrl(values.sound, values.customSound)
            if (url) {
                playTurnSound(url, values.volume)
            }
        },
        uploadCustomSound: async ({ file }) => {
            if (!file.type.startsWith('audio/')) {
                lemonToast.error('Pick an audio file, for example an MP3 or WAV file.')
                return
            }
            if (file.size > MAX_CUSTOM_TURN_SOUND_BYTES) {
                lemonToast.error(
                    `This file is too large. Pick a file smaller than ${MAX_CUSTOM_TURN_SOUND_BYTES / 1000} KB.`
                )
                return
            }
            let dataUrl: string
            try {
                dataUrl = await readFileAsDataUrl(file)
            } catch {
                lemonToast.error('Could not read this file. Try another audio file.')
                return
            }
            const duration = await readAudioDuration(dataUrl)
            if (duration === null) {
                lemonToast.error('Your browser cannot play this file. Try an MP3 or WAV file.')
                return
            }
            if (isCustomTurnSoundTooLong(duration)) {
                lemonToast.error(
                    `This sound is too long. Pick a sound of ${MAX_CUSTOM_TURN_SOUND_SECONDS} seconds or less.`
                )
                return
            }
            actions.setCustomSound({ name: file.name, dataUrl })
            actions.setSound('custom')
        },
    })),
    afterMount(({ actions, values }) => {
        // The reducer default reads the permission once at import. The user can change it after that.
        if (values.isNotificationSupported) {
            actions.setPermission(Notification.permission)
        }
    }),
])
