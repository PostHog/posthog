const NOTIFICATION_ICON = '/static/posthog-icon.svg'

const isNotificationSupported = (): boolean => typeof window !== 'undefined' && 'Notification' in window

/** The user is in another tab, another app, or another window, so the thread is not in view. */
const isUserAway = (): boolean => document.visibilityState === 'hidden' || !document.hasFocus()

