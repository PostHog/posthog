function uniqueBy<T>(items: T[], keyOf: (item: T) => string): T[] {
    const seen = new Set<string>()
    return items.filter((item) => {
        const itemKey = keyOf(item)
        const isNew = !seen.has(itemKey)
        seen.add(itemKey)
        return isNew
    })
}

/**
 * What a send carries before dedupe. A surface that pins its context replaces the page's items, and still sends picks.
 */
export function chatSendItems(
    pageItems: AttachedContextItem[],
    picks: AttachedContextItem[],
    pinnedItems?: AttachedContextItem[]
): AttachedContextItem[] {
    return uniqueBy([...(pinnedItems ?? pageItems), ...picks], attachedContextItemKey)
}

