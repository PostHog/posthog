const chatKey = (_: unknown, props: ChatContextLogicProps): string => props.taskId || NEW_CHAT_KEY

/**
 * The one definition of what is in a chat: its saved chips, the items it takes from the current page, and its picks.
 * A new chat has no saved chips and takes everything on the page. A started chat keeps the chips it saved and takes
 * only the hidden items, because a visible item reaches it only through a pick.
 */
export const chatContextLogic: LogicWrapper<chatContextLogicType> = kea<chatContextLogicType>([
    props({} as ChatContextLogicProps),
    key(({ taskId }) => taskId || NEW_CHAT_KEY),
    path((logicKey) => ['products', 'posthog_ai', 'frontend', 'logics', 'chatContextLogic', logicKey]),

    connect(() => ({
        values: [attachedContextLogic, ['contextItems', 'chatChipsByTask', 'pickedByChat', 'removedGroupsByTask']],
        actions: [attachedContextLogic, ['dismissContext', 'removeChatChip', 'removePickedItem']],
    })),

    actions({
        removeChip: (chip: ContextChip) => ({ chip }),
    }),

    selectors({
        picks: [
            (s) => [s.pickedByChat, chatKey],
            (pickedByChat: Record<string, AttachedContextItem[]>, chat: string): AttachedContextItem[] =>
                pickedByChat[chat] ?? [],
        ],
        pageItems: [
            (s) => [s.contextItems, s.removedGroupsByTask, (_, p: ChatContextLogicProps) => p.taskId],
            (
                contextItems: AttachedContextItem[],
                removedGroupsByTask: Record<string, string[]>,
                taskId?: string
            ): AttachedContextItem[] => {
                if (!taskId) {
                    return contextItems
                }
                const removedGroups = removedGroupsByTask[taskId] ?? []
                return contextItems.filter(
                    (item) => item.hidden && !(item.dismissGroup && removedGroups.includes(item.dismissGroup))
                )
            },
        ],
        chips: [
            (s) => [s.chatChipsByTask, s.pageItems, s.picks, chatKey],
            (
                chatChipsByTask: ChatChipsByTask,
                pageItems: AttachedContextItem[],
                picks: AttachedContextItem[],
                chat: string
            ): ContextChip[] =>
                uniqueBy(
                    [
                        ...(chatChipsByTask[chat] ?? []),
                        ...pageItems.filter((item) => !item.hidden && !item.previewHtml).map(contextChip),
                        ...picks.map(contextChip),
                    ],
                    (chip) => chip.id
                ),
        ],
        attachments: [
            (s) => [s.pageItems],
            (pageItems: AttachedContextItem[]): ContextAttachment[] =>
                pageItems.flatMap((item) =>
                    !item.hidden && item.previewHtml ? [{ chip: contextChip(item), previewHtml: item.previewHtml }] : []
                ),
        ],
    }),

    listeners(({ actions, values, props }) => ({
        removeChip: ({ chip }) => {
            actions.removePickedItem(chip.id, props.taskId)
            if (props.taskId) {
                actions.removeChatChip(props.taskId, chip.id, chip.dismissGroup)
            } else if (values.pageItems.some((item: AttachedContextItem) => attachedContextItemKey(item) === chip.id)) {
                actions.dismissContext(chip.id, chip.dismissGroup)
            }
        },
    })),
])
