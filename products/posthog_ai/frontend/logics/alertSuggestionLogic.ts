export const alertSuggestionLogic: LogicWrapper<alertSuggestionLogicType> = kea<alertSuggestionLogicType>([
    props({} as TurnSuggestionLogicProps),
    key((props) => `${props.streamKey}:${props.turnIndex}`),
    path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'alertSuggestionLogic', key]),
    connect((props: TurnSuggestionLogicProps) => ({
        values: [
            turnSuggestionLogic(props),
            ['suggestion as baseSuggestion'],
            slackDestinationLogic(props),
            ['slackIntegrationId', 'slackChannel', 'slackDestinationDisabledReason'],
            projectLogic,
            ['currentProjectId'],
            userLogic,
            ['user'],
        ],
        actions: [turnSuggestionLogic(props), ['markCompleted']],
    })),
    actions({
        setDirection: (direction: AlertSuggestionDirection) => ({ direction }),
        setChangePercent: (changePercent: number) => ({ changePercent }),
    }),
    loaders(({ values, props }) => ({
        createdAlert: [
            null as CreatedAlert | null,
            {
                createAlert: async () => {
                    const { suggestion, direction, changePercent, slackIntegrationId, slackChannel, currentProjectId } =
                        values
                    const userId = values.user?.id
                    if (
                        !suggestion ||
                        slackIntegrationId === null ||
                        !slackChannel ||
                        currentProjectId === null ||
                        userId === undefined
                    ) {
                        return values.createdAlert
                    }
                    const insightId =
                        suggestion.alert.insightId ??
                        (await getInsightId(suggestion.alert.insightShortId as InsightShortId))
                    if (insightId === undefined) {
                        throw new Error('The insight this alert watches could not be found')
                    }
                    const projectId = String(currentProjectId)
                    const alert = await alertsCreate(
                        projectId,
                        buildAlertCreatePayload({ suggestion, direction, changePercent, insightId, userId })
                    )
                    let slackConnected = true
                    try {
                        await alertsDestinationsCreate(
                            projectId,
                            alert.id,
                            buildAlertDestinationPayload({ slackIntegrationId, slackChannel })
                        )
                    } catch {
                        // The alert exists, so the card reports it and points at where to add the channel.
                        slackConnected = false
                    }
                    posthog.capture('posthog ai turn suggestion alert created', {
                        ...turnSuggestionEventProperties(props, suggestion),
                        direction,
                        change_percent: changePercent,
                        slack_connected: slackConnected,
                    })
                    return { alert, slackConnected }
                },
            },
        ],
    })),
    reducers({
        directionOverride: [
            null as AlertSuggestionDirection | null,
            {
                setDirection: (_, { direction }) => direction,
            },
        ],
        changePercentOverride: [
            null as number | null,
            {
                setChangePercent: (_, { changePercent }) => changePercent,
            },
        ],
        createError: [
            null as string | null,
            {
                createAlert: () => null,
                createAlertFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        suggestion: [
            (s) => [s.baseSuggestion],
            (baseSuggestion: TurnSuggestion | null): AlertTurnSuggestion | null =>
                baseSuggestion?.kind === 'alert' ? baseSuggestion : null,
        ],
        direction: [
            (s) => [s.directionOverride, s.suggestion],
            (
                directionOverride: AlertSuggestionDirection | null,
                suggestion: AlertTurnSuggestion | null
            ): AlertSuggestionDirection => directionOverride ?? suggestion?.alert.direction ?? 'decrease',
        ],
        changePercent: [
            (s) => [s.changePercentOverride, s.suggestion],
            (changePercentOverride: number | null, suggestion: AlertTurnSuggestion | null): number =>
                changePercentOverride ?? suggestion?.alert.changePercent ?? 20,
        ],
        createDisabledReason: [
            (s) => [
                s.createdAlertLoading,
                s.currentProjectId,
                s.user,
                s.changePercent,
                s.slackDestinationDisabledReason,
            ],
            (
                createdAlertLoading: boolean,
                currentProjectId: number | null,
                user: UserType | null,
                changePercent: number,
                slackDestinationDisabledReason: string | null
            ): string | null => {
                if (createdAlertLoading) {
                    return 'Creating the alert'
                }
                if (currentProjectId === null || !user) {
                    return 'Project is still loading'
                }
                if (!(changePercent > 0)) {
                    return 'Enter a change above zero'
                }
                return slackDestinationDisabledReason
            },
        ],
        alertUrl: [
            (s) => [s.createdAlert],
            (createdAlert: CreatedAlert | null): string | null =>
                createdAlert ? urls.alert(createdAlert.alert.id) : null,
        ],
    }),
    listeners(({ actions, values, props }) => ({
        createAlertSuccess: () => {
            actions.markCompleted()
        },
        createAlertFailure: ({ error }) => {
            if (values.suggestion) {
                posthog.capture('posthog ai turn suggestion alert creation failed', {
                    ...turnSuggestionEventProperties(props, values.suggestion),
                    error,
                })
            }
        },
    })),
])
