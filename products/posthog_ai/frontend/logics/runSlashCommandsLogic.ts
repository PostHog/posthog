/** The output of `/btw` or `/usage`, shown above the composer until dismissed. `body` is null while loading. */
export interface CommandResult {
    title: string
    body: string | null
}

export function formatUsageSummary(usage: ContextUsage | null): string {
    const lines: string[] = []
    const tokens = usage?.tokens
    if (typeof tokens?.inputTokens === 'number') {
        lines.push(`- Input tokens: ${humanFriendlyNumber(tokens.inputTokens)}`)
    }
    if (typeof tokens?.outputTokens === 'number') {
        lines.push(`- Output tokens: ${humanFriendlyNumber(tokens.outputTokens)}`)
    }
    if (typeof tokens?.cachedReadTokens === 'number') {
        lines.push(`- Cached tokens read: ${humanFriendlyNumber(tokens.cachedReadTokens)}`)
    }
    if (typeof tokens?.cachedWriteTokens === 'number') {
        lines.push(`- Cached tokens written: ${humanFriendlyNumber(tokens.cachedWriteTokens)}`)
    }
    if (typeof usage?.used === 'number' && typeof usage.size === 'number' && usage.size > 0) {
        const percentage = Math.min(100, Math.round((usage.used / usage.size) * 100))
        lines.push(
            `- Context window: ${humanFriendlyNumber(usage.used)} of ${humanFriendlyNumber(usage.size)} tokens (${percentage}%)`
        )
    }
    if (typeof usage?.cost === 'number') {
        lines.push(`- Cost: $${usage.cost.toFixed(2)}`)
    }
    return lines.length > 0
        ? lines.join('\n')
        : "This run hasn't reported usage yet. Try again after the agent replies."
}

