// The poller is refcounted across subscribers, so only a card that started it stops it.
function stopIntegrationsPolling(
    actions: slackDestinationLogicType['actions'],
    cache: slackDestinationLogicType['cache']
): void {
    if (cache.pollingIntegrations) {
        actions.stopPolling()
        cache.pollingIntegrations = false
    }
}

/**
 * The Slack workspace and channel a card posts to, shared by every kind that ends in Slack. Connecting
 * a workspace happens in another tab, so the choice fills in through a refetch when the user returns.
 */
export const slackDestinationLogic: LogicWrapper<slackDestinationLogicType> = kea<slackDestinationLogicType>([
    props({} as TurnSuggestionLogicProps),
    key((props) => `${props.streamKey}:${props.turnIndex}`),
    path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'slackDestinationLogic', key]),
    connect((props: TurnSuggestionLogicProps) => ({
        values: [
            turnSuggestionLogic(props),
            ['suggestion'],
            integrationsLogic,
            ['slackIntegrations', 'integrationsLoading'],
        ],
        actions: [
            integrationsLogic,
            ['startPolling', 'stopPolling', 'loadIntegrations', 'loadIntegrationsSuccess'],
            turnSuggestionLogic(props),
            ['dismiss'],
            runStreamLogic({ streamKey: props.streamKey }),
            ['markTurnSuggestionAccepted'],
        ],
    })),
    actions({
        setSlackIntegrationId: (integrationId: number | null) => ({ integrationId }),
        setSlackChannel: (channel: string | null) => ({ channel }),
        connectSlackClicked: true,
    }),
    reducers({
        slackIntegrationId: [
            null as number | null,
            {
                setSlackIntegrationId: (_, { integrationId }) => integrationId,
            },
        ],
        slackChannel: [
            null as string | null,
            {
                setSlackChannel: (_, { channel }) => channel,
                // A channel belongs to one workspace, so switching workspace clears it.
                setSlackIntegrationId: () => null,
            },
        ],
        waitingForSlack: [
            false,
            {
                connectSlackClicked: () => true,
                setSlackIntegrationId: (state, { integrationId }) => (integrationId === null ? state : false),
                dismiss: () => false,
                markTurnSuggestionAccepted: () => false,
            },
        ],
    }),
    selectors({
        hasSlackWorkspace: [
            (s) => [s.slackIntegrations],
            (slackIntegrations: IntegrationType[] | undefined): boolean => !!slackIntegrations?.length,
        ],
        slackChannelLabel: [
            (s) => [s.slackChannel],
            (slackChannel: string | null): string => (slackChannel ? slackChannelDisplayName(slackChannel) : 'Slack'),
        ],
        slackDestinationDisabledReason: [
            (s) => [s.slackIntegrationId, s.slackChannel, s.hasSlackWorkspace],
            (
                slackIntegrationId: number | null,
                slackChannel: string | null,
                hasSlackWorkspace: boolean
            ): string | null => {
                if (slackIntegrationId === null) {
                    return hasSlackWorkspace ? 'Choose a Slack workspace first' : 'Connect Slack first'
                }
                if (!slackChannel) {
                    return 'Choose a Slack channel first'
                }
                return null
            },
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        const stopWaitingForSlack = (): void => stopIntegrationsPolling(actions, cache)
        return {
            connectSlackClicked: () => {
                if (values.suggestion) {
                    captureTurnSuggestionEvent('connect slack clicked', props, values.suggestion)
                }
                // The OAuth flow runs in another tab, so the workspace shows up here only through the
                // integrations poller, which also refetches when this window regains focus. The poller
                // counts subscribers, so a second click must not add one that nothing stops.
                if (!cache.pollingIntegrations) {
                    actions.startPolling()
                    cache.pollingIntegrations = true
                }
            },
            loadIntegrationsSuccess: ({ integrations }) => {
                if (!values.waitingForSlack) {
                    return
                }
                const workspace = integrations.find((integration) => integration.kind === 'slack')
                if (workspace) {
                    actions.setSlackIntegrationId(workspace.id)
                    stopWaitingForSlack()
                }
            },
            dismiss: stopWaitingForSlack,
            markTurnSuggestionAccepted: stopWaitingForSlack,
        }
    }),
    beforeUnmount(({ cache, actions }) => stopIntegrationsPolling(actions, cache)),
])
