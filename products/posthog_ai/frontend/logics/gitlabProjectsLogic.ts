import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { ApiConfig } from 'lib/api'
import { FEATURE_FLAGS } from 'lib/constants'
import { integrationsLogic } from 'lib/integrations/integrationsLogic'
import { type FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'

import type { IntegrationType } from '~/types'

import { integrationsGitlabProjectsRetrieve } from 'products/integrations/frontend/generated/api'

import {
    type CombinedGitlabProjects,
    combineGitlabProjects,
    type GitlabProjectsResult,
    isGitlabComIntegration,
} from '../utils/gitlabProjects'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface gitlabProjectsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    providerIntegrations: IntegrationType[] | null // integrationsLogic
    gitlabProjectResults: GitlabProjectsResult[] | null
    gitlabProjectResultsLoading: boolean
    gitlabProjects: CombinedGitlabProjects | null
    gitlabTaskIntegrations: IntegrationType[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface gitlabProjectsLogicActions {
    loadGitlabProjects: () => any
    loadGitlabProjectsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadGitlabProjectsSuccess: (
        gitlabProjectResults: GitlabProjectsResult[],
        payload?: any
    ) => {
        gitlabProjectResults: GitlabProjectsResult[]
        payload?: any
    }
    openGitlabProjectPicker: () => {
        value: true
    }
    reportGitlabProjectPicked: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface gitlabProjectsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        gitlabTaskIntegrations: (
            featureFlags: FeatureFlagsSet,
            providerIntegrations: IntegrationType[] | null
        ) => IntegrationType[]
        gitlabProjects: (gitlabProjectResults: GitlabProjectsResult[] | null) => CombinedGitlabProjects | null
    }
}

export type gitlabProjectsLogicType = MakeLogicType<
    gitlabProjectsLogicValues,
    gitlabProjectsLogicActions,
    Record<string, any>,
    gitlabProjectsLogicMeta
>

/** The gitlab.com projects a coding task can run in, one per GitLab connection. */
export const gitlabProjectsLogic = kea<gitlabProjectsLogicType>([
    path(['products', 'posthog_ai', 'frontend', 'logics', 'gitlabProjectsLogic']),

    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], integrationsLogic, ['providerIntegrations']],
    })),

    actions({
        openGitlabProjectPicker: true,
        reportGitlabProjectPicked: true,
    }),

    loaders(({ values }) => ({
        gitlabProjectResults: [
            null as GitlabProjectsResult[] | null,
            {
                loadGitlabProjects: async () => {
                    const projectId = String(ApiConfig.getCurrentProjectId())
                    return await Promise.all(
                        values.gitlabTaskIntegrations.map(async ({ id }): Promise<GitlabProjectsResult> => {
                            try {
                                return {
                                    integrationId: id,
                                    response: await integrationsGitlabProjectsRetrieve(projectId, id),
                                }
                            } catch {
                                return { integrationId: id, response: null }
                            }
                        })
                    )
                },
            },
        ],
    })),

    selectors({
        gitlabTaskIntegrations: [
            (s) => [s.featureFlags, s.providerIntegrations],
            (featureFlags: FeatureFlagsSet, providerIntegrations: IntegrationType[] | null): IntegrationType[] =>
                featureFlags[FEATURE_FLAGS.TASKS_GITLAB]
                    ? (providerIntegrations ?? []).filter(isGitlabComIntegration)
                    : [],
        ],
        gitlabProjects: [
            (s) => [s.gitlabProjectResults],
            (gitlabProjectResults: GitlabProjectsResult[] | null): CombinedGitlabProjects | null =>
                gitlabProjectResults ? combineGitlabProjects(gitlabProjectResults) : null,
        ],
    }),

    listeners(({ actions, values }) => ({
        // Each open refetches, so a connection added or reconnected since the last open shows up.
        openGitlabProjectPicker: () => {
            posthog.capture('task composer gitlab projects opened')
            actions.loadGitlabProjects()
        },
        reportGitlabProjectPicked: () => {
            posthog.capture('task composer gitlab project picked')
        },
        loadGitlabProjectsSuccess: () => {
            const combined = values.gitlabProjects
            posthog.capture('task composer gitlab projects loaded', {
                project_count: combined?.projects.length ?? 0,
                load_failed: combined?.loadFailed ?? false,
                missing_scopes: combined?.missingScopes ?? [],
            })
        },
    })),
])
