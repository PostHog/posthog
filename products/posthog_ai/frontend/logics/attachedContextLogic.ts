type DismissalsByScope = Record<string, Record<string, true>>

const NO_SCOPE: string = ''
const NO_DISMISSALS: Record<string, true> = {}

function currentDismissScope(): string {
    return attachedContextLogic.findMounted()?.values.dismissScope ?? NO_SCOPE
}

function addDismissal(state: DismissalsByScope, scope: string, name: string): DismissalsByScope {
    return { ...state, [scope]: { ...state[scope], [name]: true as const } }
}

function removeDismissal(state: DismissalsByScope, scope: string, name: string): DismissalsByScope {
    const scopeDismissals = state[scope]
    if (!scopeDismissals || !(name in scopeDismissals)) {
        return state
    }
    const { [name]: _dropped, ...rest } = scopeDismissals
    return { ...state, [scope]: rest }
}

