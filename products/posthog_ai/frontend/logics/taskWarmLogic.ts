import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers } from 'kea'
import posthog from 'posthog-js'

import { projectLogic } from 'scenes/projectLogic'

import { tasksRunsCommandCreate, tasksWarmCreate } from 'products/tasks/frontend/generated/api'
import type { WarmTaskRequestApi } from 'products/tasks/frontend/generated/api.schemas'

/** Debounce before warming, measured from the keystroke that first made the draft non-empty. */
const WARM_DEBOUNCE_MS = 250
/** Grace period after the draft empties before the warm sandbox is released. */
const RELEASE_AFTER_EMPTY_MS = 5000

/**
 * A warm sandbox the backend is holding for this composer. `key` is the selection the warm was booted
 * for — repo, branch, runtime, model, permission mode — so a later change to any of them invalidates it.
 */
export interface WarmLease {
    key: string
    taskId: string
    runId: string
}

export interface TaskWarmLogicProps {
    /** Matches `taskTrackerSceneLogicProps.panelId` so each composer instance owns its own lease. */
    panelId?: string
}

/**
 * Build the lease key from the fields the backend matches a warm Run on. Reasoning effort is
 * deliberately excluded: activation applies the final effort before the first turn, so changing it must
 * not throw the warm away (`_find_idling_warm_run` omits it from the match for the same reason).
 */
export function warmLeaseKey(request: WarmTaskRequestApi): string {
    return [
        request.repository ?? '',
        (request.repositories ?? []).join(','),
        request.github_integration ?? '',
        request.branch ?? '',
        request.runtime_adapter ?? '',
        request.model ?? '',
        request.initial_permission_mode ?? '',
    ].join('|')
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface taskWarmLogicValues {
    currentProjectId: number | null // projectLogic
    warmLease: WarmLease | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface taskWarmLogicActions {
    noteDraft: (
        hasText: boolean,
        request: WarmTaskRequestApi
    ) => {
        hasText: boolean
        request: WarmTaskRequestApi
    }
    prewarm: (request: WarmTaskRequestApi) => {
        request: WarmTaskRequestApi
    }
    releaseWarm: () => {
        value: true
    }
    consumeWarm: () => {
        value: true
    }
    setWarmLease: (lease: WarmLease | null) => {
        lease: WarmLease | null
    }
}

export type taskWarmLogicType = MakeLogicType<taskWarmLogicValues, taskWarmLogicActions, TaskWarmLogicProps>

/**
 * Boots a sandbox while the user is still typing, so submitting a task lands on one that is already up.
 *
 * A cold PostHog AI task spends ~16s provisioning and booting the agent server before the typed message
 * even reaches the agent. Warming moves that off the user's perceived path; it does not make the boot
 * faster. Best-effort throughout — every failure just means the submit takes the cold path.
 *
 * Ported from `scenes/max/maxThreadLogic`'s prewarm, which drives the legacy conversations route. This
 * one drives the tasks warm endpoint instead, which is what the `/tasks` composer submits through.
 */
export const taskWarmLogic = kea<taskWarmLogicType>([
    path(['products', 'posthog_ai', 'frontend', 'logics', 'taskWarmLogic']),
    props({} as TaskWarmLogicProps),
    key((props) => props.panelId ?? 'scene'),

    connect({
        values: [projectLogic, ['currentProjectId']],
    }),

    actions({
        noteDraft: (hasText: boolean, request: WarmTaskRequestApi) => ({ hasText, request }),
        prewarm: (request: WarmTaskRequestApi) => ({ request }),
        releaseWarm: true,
        consumeWarm: true,
        setWarmLease: (lease: WarmLease | null) => ({ lease }),
    }),

    reducers({
        warmLease: [
            null as WarmLease | null,
            {
                setWarmLease: (_, { lease }) => lease,
            },
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        noteDraft: ({ hasText, request }) => {
            if (!hasText) {
                // Draft emptied — drop a pending warm and schedule a release, so a user who clears the
                // box and walks away doesn't leave a sandbox idling until the server-side reaper.
                cache.disposables.dispose('warm-debounce')
                if (values.warmLease || cache.warming) {
                    cache.disposables.add(() => {
                        const timer = setTimeout(() => actions.releaseWarm(), RELEASE_AFTER_EMPTY_MS)
                        return () => clearTimeout(timer)
                    }, 'warm-release')
                }
                return
            }
            cache.disposables.dispose('warm-release')
            const key = warmLeaseKey(request)
            if (values.warmLease?.key === key || cache.warmingKey === key) {
                return
            }
            // The selection changed out from under an existing warm (a different repo, branch, model or
            // permission mode); that sandbox can no longer serve this submit, so let it go and warm again.
            if (values.warmLease) {
                actions.releaseWarm()
            }
            cache.disposables.add(() => {
                const timer = setTimeout(() => actions.prewarm(request), WARM_DEBOUNCE_MS)
                return () => clearTimeout(timer)
            }, 'warm-debounce')
        },

        prewarm: async ({ request }) => {
            cache.disposables.dispose('warm-debounce')
            const key = warmLeaseKey(request)
            if (values.currentProjectId == null || cache.warming || values.warmLease?.key === key) {
                return
            }
            cache.warming = true
            cache.warmingKey = key
            cache.pendingRelease = false
            try {
                const warm = await tasksWarmCreate(String(values.currentProjectId), request)
                // An empty body is the documented "not warmed" answer — the flag is off, the pool is
                // full, or the integration didn't resolve. Not an error, just no speedup this time.
                if (warm?.task_id && warm?.run_id) {
                    actions.setWarmLease({ key, taskId: warm.task_id, runId: warm.run_id })
                }
                // The user may have abandoned the draft while this POST was in flight, in which case the
                // release hit the early-exit below with nothing to release. Honor that intent now so the
                // freshly warmed sandbox isn't left for the reaper.
                if (cache.pendingRelease) {
                    cache.pendingRelease = false
                    actions.releaseWarm()
                }
            } catch (error) {
                posthog.captureException(error)
            } finally {
                cache.warming = false
                cache.warmingKey = null
            }
        },

        releaseWarm: async () => {
            cache.disposables.dispose('warm-debounce')
            cache.disposables.dispose('warm-release')
            const lease = values.warmLease
            if (!lease) {
                // Nothing to release yet. If a warm POST is still in flight, record the intent so its
                // completion releases rather than dropping the request on the floor.
                if (cache.warming) {
                    cache.pendingRelease = true
                }
                return
            }
            actions.setWarmLease(null)
            if (values.currentProjectId == null) {
                return
            }
            try {
                // Cancel drives the Run terminal, which drops it out of the warm-pool count immediately
                // instead of waiting out the server's idle timeout.
                await tasksRunsCommandCreate(String(values.currentProjectId), lease.taskId, lease.runId, {
                    jsonrpc: '2.0',
                    method: 'cancel',
                })
            } catch (error) {
                posthog.captureException(error)
            }
        },

        consumeWarm: () => {
            // A submitted message consumes the warm: that Run is the one the submit activates, so drop
            // every timer and the lease WITHOUT cancelling it.
            cache.disposables.dispose('warm-debounce')
            cache.disposables.dispose('warm-release')
            cache.pendingRelease = false
            actions.setWarmLease(null)
        },
    })),
])
