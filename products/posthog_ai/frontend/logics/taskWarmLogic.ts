import { MakeLogicType, actions, beforeUnmount, connect, kea, key, listeners, path, props, reducers } from 'kea'
import posthog from 'posthog-js'

import { projectLogic } from 'scenes/projectLogic'

import { tasksRunsCancelCreate, tasksWarmCreate, tasksWarmResumeCreate } from 'products/tasks/frontend/generated/api'
import type { WarmTaskRequestApi, WarmTaskResumeRequestApi } from 'products/tasks/frontend/generated/api.schemas'

/** Debounce before warming, measured from the keystroke that first made the draft non-empty. */
const WARM_DEBOUNCE_MS = 600
/** Grace period after the draft empties before the warm sandbox is released. */
const RELEASE_AFTER_EMPTY_MS = 5000

export interface WarmLease {
    key: string
    taskId: string
    runId: string
    configurationKey?: string
    permissionModeMutable?: boolean
}

export interface WarmSubmission {
    projectId: string
    lease: WarmLease | null
    runId?: string | null
    superseded?: boolean
}

export interface TaskWarmLogicProps {
    /** Matches `taskTrackerSceneLogicProps.panelId` so each composer instance owns its own lease. */
    panelId?: string
    taskId?: string
    resumeFromRunId?: string
}

export type TaskWarmRequest = WarmTaskRequestApi | WarmTaskResumeRequestApi

/**
 * Build the lease key from the fields the backend matches a warm Run on. Reasoning effort is
 * deliberately excluded: activation applies the final effort before the first turn, so changing it must
 * not throw the warm away (`_find_idling_warm_run` omits it from the match for the same reason).
 */
export function warmLeaseKey(request: TaskWarmRequest, ignorePermissionMode = false): string {
    if ('resume_from_run_id' in request) {
        return [
            request.resume_from_run_id,
            request.runtime_adapter ?? '',
            request.model ?? '',
            ignorePermissionMode ? '' : (request.initial_permission_mode ?? ''),
        ].join('|')
    }
    return [
        request.repository ?? '',
        (request.repositories ?? []).join(','),
        request.github_integration ?? '',
        request.branch ?? '',
        request.runtime_adapter ?? '',
        request.model ?? '',
        ignorePermissionMode ? '' : (request.initial_permission_mode ?? ''),
        request.sandbox_environment_id ?? '',
        request.custom_image_id ?? '',
    ].join('|')
}

function matchesWarmLease(lease: WarmLease | null, request: TaskWarmRequest): boolean {
    return (
        !!lease &&
        (lease.key === warmLeaseKey(request) ||
            (lease.permissionModeMutable === true && lease.configurationKey === warmLeaseKey(request, true)))
    )
}

/**
 * Cancel a warm Run, which drives it terminal so it drops out of the warm-pool count immediately
 * instead of waiting out the server's idle timeout. Best-effort: a failed cancel just leaves the Run
 * for the server-side reaper.
 *
 * The run-level `cancel` endpoint, NOT the `cancel` relay command the streaming surfaces use: that one
 * is proxied to the agent server to abort the turn in flight, and a warm Run has no turn. It answers
 * `{cancelled: true}` and leaves the Run idling until the inactivity timer reclaims it, so the pool
 * slot stays held and the miss is booked as `idle_timeout` rather than `released`.
 *
 * `only_if_awaiting_first_message` makes the server refuse to stop a Run that has since been activated.
 * A lease is not exclusive: the backend hands the same warm Run to every composer holding the same
 * selection, so a submit in one composer can activate the Run another composer is still holding. Without
 * the fence, that composer releasing — on unmount, an emptied draft, or a selection change — would stop
 * the run the user just started.
 */
async function cancelWarmRun(projectId: string, lease: WarmLease): Promise<void> {
    try {
        await tasksRunsCancelCreate(projectId, lease.taskId, lease.runId, {
            only_if_awaiting_first_message: true,
        })
    } catch (error) {
        posthog.captureException(error)
    }
}

async function releaseUnusedWarm(submission: WarmSubmission): Promise<void> {
    // A failed or aborted submission may still deliver its message. Leave uncertain warms to the reaper.
    if (
        !submission.superseded &&
        submission.runId !== undefined &&
        submission.lease &&
        submission.lease.runId !== submission.runId
    ) {
        await cancelWarmRun(submission.projectId, submission.lease)
    }
}

