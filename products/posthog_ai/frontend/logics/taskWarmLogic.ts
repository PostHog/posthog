export type taskWarmLogicType = MakeLogicType<
    taskWarmLogicValues,
    taskWarmLogicActions,
    TaskWarmLogicProps,
    taskWarmLogicMeta
>

/**
 * Boots a sandbox while the user is still typing, so submitting a task lands on one that is already up.
 *
 * A cold PostHog AI task spends ~16s provisioning and booting the agent server before the typed message
 * even reaches the agent. Warming moves that off the user's perceived path; it does not make the boot
 * faster. Best-effort throughout — every failure just means the submit takes the cold path.
 *
 * Ported from `scenes/max/maxThreadLogic`'s prewarm, which drives the legacy conversations route. This
 * one drives the tasks warm endpoint instead, which is what the `/tasks` composer submits through.
 */
export const taskWarmLogic = kea<taskWarmLogicType>([
    path(['products', 'posthog_ai', 'frontend', 'logics', 'taskWarmLogic']),
    props({} as TaskWarmLogicProps),
    key((props) => props.panelId ?? ([props.taskId, props.resumeFromRunId].filter(Boolean).join(':') || 'scene')),

    connect({
        values: [projectLogic, ['currentProjectId']],
    }),

    actions({
        noteDraft: (hasText: boolean, request: TaskWarmRequest, eligible: boolean = true) => ({
            hasText,
            request,
            eligible,
        }),
        prewarm: (request: TaskWarmRequest) => ({ request }),
        prepareSubmit: (submission: WarmSubmission) => ({ submission }),
        releaseWarm: true,
        consumeWarm: (submission: WarmSubmission, runId: string | null) => ({ submission, runId }),
        setWarmLease: (lease: WarmLease | null) => ({ lease }),
    }),

    reducers({
        warmLease: [
            null as WarmLease | null,
            {
                setWarmLease: (_, { lease }) => lease,
            },
        ],
    }),

    listeners(({ actions, values, cache, props }) => ({
        noteDraft: ({ hasText, request, eligible }) => {
            if (!hasText) {
                // Draft emptied — drop a pending warm and schedule a release, so a user who clears the
                // box and walks away doesn't leave a sandbox idling until the server-side reaper.
                cache.disposables.dispose('warm-debounce')
                // Also drop any selection queued behind an in-flight warm, so an abandon isn't followed
                // by a re-warm for a selection the user no longer wants.
                cache.pendingWarmRequest = null
                if (cache.warmAttempted || values.warmLease || cache.warming) {
                    cache.disposables.add(
                        () => {
                            const timer = setTimeout(() => {
                                cache.warmAttempted = false
                                actions.releaseWarm()
                            }, RELEASE_AFTER_EMPTY_MS)
                            return () => clearTimeout(timer)
                        },
                        'warm-release',
                        { pauseOnPageHidden: false }
                    )
                }
                return
            }
            cache.disposables.dispose('warm-release')
            if (!eligible) {
                cache.pendingWarmRequest = null
                actions.releaseWarm()
                return
            }
            const key = warmLeaseKey(request)
            if (matchesWarmLease(values.warmLease, request) || cache.warmingKey === key) {
                cache.warmAttempted = true
                // Re-engaging the selection we already warmed or are still warming. A release may have
                // raced the in-flight POST and deferred itself via pendingRelease; clear it so the warm
                // that lands is kept for this submit rather than cancelled out from under the user.
                cache.pendingRelease = false
                cache.pendingWarmRequest = null
                return
            }
            if (cache.warming) {
                cache.pendingWarmRequest = request
                cache.pendingRelease = false
                return
            }
            if (values.warmLease) {
                actions.releaseWarm()
            }
            if (cache.warmAttempted) {
                return
            }
            cache.disposables.add(() => {
                const timer = setTimeout(() => actions.prewarm(request), WARM_DEBOUNCE_MS)
                return () => clearTimeout(timer)
            }, 'warm-debounce')
        },

        prewarm: async ({ request }) => {
            cache.disposables.dispose('warm-debounce')
            const key = warmLeaseKey(request)
            if (values.currentProjectId == null || matchesWarmLease(values.warmLease, request)) {
                return
            }
            // Route on the payload, not on `props.taskId`: the request shape is what each endpoint
            // accepts, and only a resume request names a source run. The scene composer mounts this logic
            // under the `/tasks/:taskId` route param, so `props.taskId` can be the `new` sentinel — a
            // fresh-task body posted to `tasks/new/warm/` is rejected for the missing `resume_from_run_id`
            // and that composer never warms at all.
            const resumeRequest = 'resume_from_run_id' in request ? request : null
            if (resumeRequest && !props.taskId) {
                return
            }
            if (cache.warming) {
                if (cache.warmingKey !== key) {
                    cache.pendingWarmRequest = request
                }
                return
            }
            if (cache.warmAttempted) {
                return
            }
            cache.warmAttempted = true
            cache.warming = true
            cache.warmingKey = key
            cache.pendingRelease = false
            cache.pendingWarmRequest = null
            const warmRequest: { submission: WarmSubmission | null } = { submission: null }
            cache.warmRequest = warmRequest
            const projectId = String(values.currentProjectId)
            const disposables = cache.disposables
            try {
                const warm = resumeRequest
                    ? await tasksWarmResumeCreate(projectId, props.taskId as string, resumeRequest)
                    : await tasksWarmCreate(projectId, request as WarmTaskRequestApi)
                const lease =
                    warm?.task_id && warm?.run_id
                        ? {
                              key,
                              taskId: warm.task_id,
                              runId: warm.run_id,
                              configurationKey: warmLeaseKey(request, true),
                              permissionModeMutable:
                                  !resumeRequest &&
                                  'permission_mode_mutable' in warm &&
                                  warm.permission_mode_mutable === true,
                          }
                        : null
                if (warmRequest.submission) {
                    warmRequest.submission.lease = lease
                    await releaseUnusedWarm(warmRequest.submission)
                    return
                }
                if (disposables.isDisposed) {
                    if (lease) {
                        await cancelWarmRun(projectId, lease)
                    }
                    return
                }
                // An empty body is the documented "not warmed" answer — the flag is off, the pool is
                // full, or the integration didn't resolve. Not an error, just no speedup this time.
                if (lease) {
                    actions.setWarmLease(lease)
                }
                // The user may have abandoned the draft while this POST was in flight, in which case the
                // release hit the early-exit below with nothing to release. Honor that intent now so the
                // freshly warmed sandbox isn't left for the reaper.
                if (cache.pendingRelease) {
                    cache.pendingRelease = false
                    actions.releaseWarm()
                }
            } catch (error) {
                posthog.captureException(error)
            } finally {
                cache.warming = false
                cache.warmingKey = null
                cache.warmRequest = null
            }
            const pending = cache.pendingWarmRequest
            cache.pendingWarmRequest = null
            if (pending && !matchesWarmLease(values.warmLease, pending)) {
                if (values.warmLease) {
                    actions.releaseWarm()
                }
                if (!cache.warmAttempted) {
                    actions.prewarm(pending)
                }
            }
        },

        releaseWarm: async () => {
            cache.disposables.dispose('warm-debounce')
            cache.disposables.dispose('warm-release')
            const lease = values.warmLease
            if (!lease) {
                // Nothing to release yet. If a warm POST is still in flight, record the intent so its
                // completion releases rather than dropping the request on the floor.
                if (cache.warming) {
                    cache.pendingRelease = true
                }
                return
            }
            actions.setWarmLease(null)
            if (values.currentProjectId == null) {
                return
            }
            await cancelWarmRun(String(values.currentProjectId), lease)
        },

        prepareSubmit: ({ submission }) => {
            // A warm started after submission can miss the backend's pool lookup and create an extra task.
            cache.disposables.dispose('warm-debounce')
            cache.disposables.dispose('warm-release')
            cache.pendingRelease = false
            cache.pendingWarmRequest = null
            if (values.currentProjectId == null) {
                return
            }
            // Another submission can activate the same warm, so the earlier result cannot authorize cleanup.
            if (cache.submission) {
                cache.submission.superseded = true
            }
            submission.lease = values.warmLease
            cache.submission = submission
            if (cache.warmRequest && !cache.warmRequest.submission) {
                cache.warmRequest.submission = submission
            }
            // Teardown must not cancel a run while its first message is being delivered.
            actions.setWarmLease(null)
        },

        consumeWarm: async ({ submission, runId }) => {
            submission.runId = runId
            if (cache.submission === submission && runId) {
                cache.warmAttempted = false
            }
            await releaseUnusedWarm(submission)
        },
    })),

    // Leaving the composer (this logic is connected to the scene, so it unmounts when the scene or panel
    // does) is the most common way to abandon a draft, more so than clearing the box and waiting out the
    // release timer. Cancel the held warm here too, so navigating away reclaims the sandbox immediately
    // instead of leaving it to idle until the server reaper. Cancel inline rather than dispatching
    // releaseWarm, because a listener dispatched during teardown does not run. Submitted warms belong to
    // their submission until its outcome is known. Unsubmitted warms still mid-boot are released on arrival.
    beforeUnmount(({ values }) => {
        const lease = values.warmLease
        if (lease && values.currentProjectId != null) {
            void cancelWarmRun(String(values.currentProjectId), lease)
        }
    }),
])
