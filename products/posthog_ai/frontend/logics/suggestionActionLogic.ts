/** Taking the offer: the inputs a card can change, the one request that creates it, and the result. */
export const suggestionActionLogic: LogicWrapper<suggestionActionLogicType> = kea<suggestionActionLogicType>([
    props({} as TurnSuggestionLogicProps),
    key((props) => `${props.streamKey}:${props.turnIndex}`),
    path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'suggestionActionLogic', key]),
    connect((props: TurnSuggestionLogicProps) => ({
        values: [
            turnSuggestionLogic(props),
            ['suggestion'],
            slackDestinationLogic(props),
            ['slackIntegrationId', 'slackChannel', 'slackChannelLabel', 'slackDestinationDisabledReason'],
            runStreamLogic({ streamKey: props.streamKey }),
            ['threadItems', 'toolInvocations'],
            projectLogic,
            ['currentProjectId'],
            teamLogic,
            ['currentTeamId'],
            userLogic,
            ['user'],
        ],
        actions: [runStreamLogic({ streamKey: props.streamKey }), ['markTurnSuggestionAccepted']],
    })),
    actions({
        setCadence: (cadence: ScoutSuggestionCadence) => ({ cadence }),
        setDirection: (direction: AlertSuggestionDirection) => ({ direction }),
        setChangePercent: (changePercent: number) => ({ changePercent }),
        setTitle: (title: string) => ({ title }),
        setScoutBody: (scoutBody: string) => ({ scoutBody }),
        setWorkflowPrompt: (workflowPrompt: string) => ({ workflowPrompt }),
    }),
    loaders(({ actions, values, props }) => ({
        accepted: [
            null as AcceptedSuggestion | null,
            {
                accept: async () => {
                    const { suggestion, currentProjectId, currentTeamId } = values
                    if (
                        !suggestion ||
                        currentProjectId === null ||
                        currentTeamId === null ||
                        values.acceptDisabledReason
                    ) {
                        return values.accepted
                    }
                    // The request can outlive the card: a message sent while it runs clears `values.suggestion`,
                    // so the outcome is recorded against the suggestion this accept started from.
                    let outcome: Awaited<ReturnType<typeof acceptSuggestion>>
                    try {
                        outcome = await acceptSuggestion({
                            suggestion,
                            projectId: currentProjectId,
                            teamId: currentTeamId,
                            sessionId: props.sessionId,
                            userId: values.user?.id,
                            slackIntegrationId: values.slackIntegrationId,
                            slackChannel: values.slackChannel,
                            cadence: values.cadence,
                            scoutBody: values.scoutBody,
                            direction: values.direction,
                            changePercent: values.changePercent,
                            notebookTitle: values.notebookTitle,
                            conversationBlocks: values.conversationBlocks,
                            workflowPrompt: values.workflowPrompt,
                        })
                    } catch (error) {
                        // posthog-js serializes an Error instance as an empty object.
                        captureTurnSuggestionEvent('accept failed', props, suggestion, {
                            error: error instanceof Error ? error.message : String(error),
                        })
                        throw error
                    }
                    captureTurnSuggestionEvent('accepted', props, suggestion, outcome.eventProperties)
                    actions.markTurnSuggestionAccepted(suggestion.turnIndex)
                    recordTurnSuggestionResolution(currentProjectId, props.sessionId, suggestion, 'accepted')
                    if (suggestion.kind === 'workflow') {
                        router.actions.push(outcome.accepted.url)
                    }
                    return outcome.accepted
                },
            },
        ],
    })),
    reducers({
        cadenceOverride: [null as ScoutSuggestionCadence | null, { setCadence: (_, { cadence }) => cadence }],
        directionOverride: [null as AlertSuggestionDirection | null, { setDirection: (_, { direction }) => direction }],
        changePercentOverride: [null as number | null, { setChangePercent: (_, { changePercent }) => changePercent }],
        titleOverride: [null as string | null, { setTitle: (_, { title }) => title }],
        scoutBodyOverride: [null as string | null, { setScoutBody: (_, { scoutBody }) => scoutBody }],
        workflowPromptOverride: [
            null as string | null,
            { setWorkflowPrompt: (_, { workflowPrompt }) => workflowPrompt },
        ],
        acceptFailed: [false, { accept: () => false, acceptFailure: () => true }],
    }),
    selectors({
        cadence: [
            (s) => [s.cadenceOverride, s.suggestion],
            (
                cadenceOverride: ScoutSuggestionCadence | null,
                suggestion: TurnSuggestion | null
            ): ScoutSuggestionCadence => {
                if (cadenceOverride) {
                    return cadenceOverride
                }
                if (suggestion?.kind === 'scout') {
                    return suggestion.scout.cadence
                }
                return suggestion?.kind === 'subscription' ? suggestion.subscription.cadence : 'weekly'
            },
        ],
        direction: [
            (s) => [s.directionOverride, s.suggestion],
            (
                directionOverride: AlertSuggestionDirection | null,
                suggestion: TurnSuggestion | null
            ): AlertSuggestionDirection =>
                directionOverride ?? (suggestion?.kind === 'alert' ? suggestion.alert.direction : 'decrease'),
        ],
        changePercent: [
            (s) => [s.changePercentOverride, s.suggestion],
            (changePercentOverride: number | null, suggestion: TurnSuggestion | null): number =>
                changePercentOverride ?? (suggestion?.kind === 'alert' ? suggestion.alert.changePercent : 20),
        ],
        notebookTitle: [
            (s) => [s.titleOverride, s.suggestion],
            (titleOverride: string | null, suggestion: TurnSuggestion | null): string =>
                titleOverride ?? (suggestion?.kind === 'notebook' ? suggestion.notebook.title : ''),
        ],
        scoutBody: [
            (s) => [s.scoutBodyOverride, s.suggestion],
            (scoutBodyOverride: string | null, suggestion: TurnSuggestion | null): string =>
                scoutBodyOverride ?? (suggestion?.kind === 'scout' ? suggestion.scout.body : ''),
        ],
        conversationBlocks: [
            (s) => [s.threadItems, s.toolInvocations],
            (threadItems: ThreadItem[], toolInvocations: Map<string, ToolInvocation>): ConversationBlocks =>
                collectConversationBlocks(threadItems, toolInvocations),
        ],
        workflowPrompt: [
            (s) => [s.workflowPromptOverride, s.suggestion],
            (workflowPromptOverride: string | null, suggestion: TurnSuggestion | null): string =>
                workflowPromptOverride ?? (suggestion?.kind === 'workflow' ? suggestion.workflow.prompt : ''),
        ],
        acceptDisabledReason: [
            (s) => [
                s.suggestion,
                s.currentProjectId,
                s.currentTeamId,
                s.user,
                s.slackDestinationDisabledReason,
                s.notebookTitle,
                s.changePercent,
                s.scoutBody,
                s.workflowPrompt,
                (_, p) => !!p.workflowBuilderAvailable,
            ],
            (
                suggestion: TurnSuggestion | null,
                currentProjectId: number | null,
                currentTeamId: number | null,
                user: UserType | null,
                slackDestinationDisabledReason: string | null,
                notebookTitle: string,
                changePercent: number,
                scoutBody: string,
                workflowPrompt: string,
                workflowBuilderAvailable: boolean
            ): string | null => {
                if (currentProjectId === null || currentTeamId === null || !user) {
                    return 'Your project is still loading'
                }
                switch (suggestion?.kind) {
                    case 'workflow':
                        if (!workflowBuilderAvailable) {
                            return "The AI workflow builder isn't available in this view"
                        }
                        return isValidWorkflowBrief(workflowPrompt)
                            ? null
                            : 'Add a workflow brief of up to 4,000 characters'
                    case 'scout':
                        return scoutBody.trim() ? slackDestinationDisabledReason : 'Add instructions for the scout'
                    case 'notebook':
                        return notebookTitle.trim() ? null : 'Add a notebook title'
                    case 'alert':
                        return changePercent > 0 ? slackDestinationDisabledReason : 'Enter a percentage above 0'
                    default:
                        return slackDestinationDisabledReason
                }
            },
        ],
    }),
])
