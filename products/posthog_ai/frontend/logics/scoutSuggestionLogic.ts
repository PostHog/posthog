export type scoutSuggestionLogicType = MakeLogicType<
    scoutSuggestionLogicValues,
    scoutSuggestionLogicActions,
    TurnSuggestionLogicProps,
    scoutSuggestionLogicMeta
>

export const scoutSuggestionLogic: LogicWrapper<scoutSuggestionLogicType> = kea<scoutSuggestionLogicType>([
    props({} as TurnSuggestionLogicProps),
    key((props) => `${props.streamKey}:${props.turnIndex}`),
    path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'scoutSuggestionLogic', key]),
    connect((props: TurnSuggestionLogicProps) => ({
        values: [
            turnSuggestionLogic(props),
            ['suggestion as baseSuggestion'],
            slackDestinationLogic(props),
            ['slackIntegrationId', 'slackChannel', 'slackDestinationDisabledReason'],
            projectLogic,
            ['currentProjectId'],
        ],
        actions: [turnSuggestionLogic(props), ['markCompleted']],
    })),
    actions({
        setCadence: (cadence: ScoutSuggestionCadence) => ({ cadence }),
    }),
    loaders(({ values, props }) => ({
        createdScout: [
            null as SignalScoutCreateResponseApi | null,
            {
                createScout: async () => {
                    const { suggestion, cadence, slackIntegrationId, slackChannel, currentProjectId } = values
                    if (!suggestion || slackIntegrationId === null || !slackChannel || currentProjectId === null) {
                        return values.createdScout
                    }
                    const created = await signalsScoutCreate(
                        String(currentProjectId),
                        buildScoutCreatePayload({ suggestion, cadence, slackIntegrationId, slackChannel })
                    )
                    posthog.capture('posthog ai turn suggestion scout created', {
                        ...turnSuggestionEventProperties(props, suggestion),
                        cadence,
                        scout_mode: suggestion.scout.mode,
                        scout_skill_name: created.skill.name,
                    })
                    return created
                },
            },
        ],
    })),
    reducers({
        cadenceOverride: [
            null as ScoutSuggestionCadence | null,
            {
                setCadence: (_, { cadence }) => cadence,
            },
        ],
        createError: [
            null as string | null,
            {
                createScout: () => null,
                createScoutFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        suggestion: [
            (s) => [s.baseSuggestion],
            (baseSuggestion: TurnSuggestion | null): ScoutTurnSuggestion | null =>
                baseSuggestion?.kind === 'scout' ? baseSuggestion : null,
        ],
        cadence: [
            (s) => [s.cadenceOverride, s.suggestion],
            (
                cadenceOverride: ScoutSuggestionCadence | null,
                suggestion: ScoutTurnSuggestion | null
            ): ScoutSuggestionCadence => cadenceOverride ?? suggestion?.scout.cadence ?? 'weekly',
        ],
        createDisabledReason: [
            (s) => [s.createdScoutLoading, s.currentProjectId, s.slackDestinationDisabledReason],
            (
                createdScoutLoading: boolean,
                currentProjectId: number | null,
                slackDestinationDisabledReason: string | null
            ): string | null => {
                if (createdScoutLoading) {
                    return 'Creating the scout'
                }
                if (currentProjectId === null) {
                    return 'Project is still loading'
                }
                return slackDestinationDisabledReason
            },
        ],
        scoutUrl: [
            (s) => [s.createdScout],
            (createdScout: SignalScoutCreateResponseApi | null): string | null =>
                createdScout ? urls.inboxScout(createdScout.skill.name) : null,
        ],
    }),
    listeners(({ actions, values, props }) => ({
        createScoutSuccess: () => {
            actions.markCompleted()
        },
        createScoutFailure: ({ error }) => {
            if (values.suggestion) {
                posthog.capture('posthog ai turn suggestion scout creation failed', {
                    ...turnSuggestionEventProperties(props, values.suggestion),
                    error,
                })
            }
        },
    })),
])
