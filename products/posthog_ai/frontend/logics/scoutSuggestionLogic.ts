export const scoutSuggestionLogic: LogicWrapper<scoutSuggestionLogicType> = kea<scoutSuggestionLogicType>([
    props({} as ScoutSuggestionLogicProps),
    key((props) => `${props.streamKey}:${props.turnIndex}`),
    path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'scoutSuggestionLogic', key]),
    connect((props: ScoutSuggestionLogicProps) => ({
        values: [
            runStreamLogic({ streamKey: props.streamKey }),
            ['turnSuggestions'],
            integrationsLogic,
            ['slackIntegrations', 'integrationsLoading'],
            projectLogic,
            ['currentProjectId'],
        ],
        actions: [integrationsLogic, ['startPolling', 'stopPolling', 'loadIntegrations', 'loadIntegrationsSuccess']],
    })),
    actions({
        setCadence: (cadence: ScoutSuggestionCadence) => ({ cadence }),
        setSlackIntegrationId: (integrationId: number | null) => ({ integrationId }),
        setSlackChannel: (channel: string | null) => ({ channel }),
        dismiss: true,
        reportShown: true,
        connectSlackClicked: true,
    }),
    loaders(({ values, props }) => ({
        createdScout: [
            null as SignalScoutCreateResponseApi | null,
            {
                createScout: async () => {
                    const { suggestion, cadence, slackIntegrationId, slackChannel, currentProjectId } = values
                    if (!suggestion || slackIntegrationId === null || !slackChannel || currentProjectId === null) {
                        return values.createdScout
                    }
                    const created = await signalsScoutCreate(
                        String(currentProjectId),
                        buildScoutCreatePayload({ suggestion, cadence, slackIntegrationId, slackChannel })
                    )
                    posthog.capture('posthog ai turn suggestion scout created', {
                        ...turnSuggestionEventProperties(props, suggestion),
                        cadence,
                        scout_skill_name: created.skill.name,
                    })
                    return created
                },
            },
        ],
    })),
    reducers({
        cadenceOverride: [
            null as ScoutSuggestionCadence | null,
            {
                setCadence: (_, { cadence }) => cadence,
            },
        ],
        slackIntegrationId: [
            null as number | null,
            {
                setSlackIntegrationId: (_, { integrationId }) => integrationId,
            },
        ],
        slackChannel: [
            null as string | null,
            {
                setSlackChannel: (_, { channel }) => channel,
                // A channel belongs to one workspace, so switching workspace clears it.
                setSlackIntegrationId: () => null,
            },
        ],
        dismissed: [
            false,
            {
                dismiss: () => true,
            },
        ],
        shownReported: [
            false,
            {
                reportShown: () => true,
            },
        ],
        waitingForSlack: [
            false,
            {
                connectSlackClicked: () => true,
                setSlackIntegrationId: (state, { integrationId }) => (integrationId === null ? state : false),
                dismiss: () => false,
            },
        ],
        createError: [
            null as string | null,
            {
                createScout: () => null,
                createScoutFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        suggestion: [
            (s, p) => [s.turnSuggestions, p.turnIndex],
            (turnSuggestions: Record<number, TurnSuggestion>, turnIndex: number): ScoutTurnSuggestion | null => {
                const suggestion = turnSuggestions[turnIndex]
                return suggestion?.kind === 'scout' ? suggestion : null
            },
        ],
        cadence: [
            (s) => [s.cadenceOverride, s.suggestion],
            (
                cadenceOverride: ScoutSuggestionCadence | null,
                suggestion: ScoutTurnSuggestion | null
            ): ScoutSuggestionCadence => cadenceOverride ?? suggestion?.scout.cadence ?? 'weekly',
        ],
        createDisabledReason: [
            (s) => [s.slackIntegrationId, s.slackChannel, s.currentProjectId, s.createdScoutLoading],
            (
                slackIntegrationId: number | null,
                slackChannel: string | null,
                currentProjectId: number | null,
                createdScoutLoading: boolean
            ): string | null => {
                if (createdScoutLoading) {
                    return 'Creating the scout'
                }
                if (currentProjectId === null) {
                    return 'Project is still loading'
                }
                if (slackIntegrationId === null) {
                    return 'Connect Slack first'
                }
                if (!slackChannel) {
                    return 'Choose a Slack channel first'
                }
                return null
            },
        ],
        scoutUrl: [
            (s) => [s.createdScout],
            (createdScout: SignalScoutCreateResponseApi | null): string | null =>
                createdScout ? urls.inboxScout(createdScout.skill.name) : null,
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        const stopWaitingForSlack = (): void => {
            cache.disposables.dispose('slackConnectVisibility')
            if (cache.pollingIntegrations) {
                actions.stopPolling()
                cache.pollingIntegrations = false
            }
        }
        return {
            reportShown: () => {
                if (values.suggestion) {
                    posthog.capture(
                        'posthog ai turn suggestion shown',
                        turnSuggestionEventProperties(props, values.suggestion)
                    )
                }
            },
            dismiss: () => {
                if (values.suggestion) {
                    posthog.capture(
                        'posthog ai turn suggestion dismissed',
                        turnSuggestionEventProperties(props, values.suggestion)
                    )
                }
                stopWaitingForSlack()
            },
            connectSlackClicked: () => {
                if (values.suggestion) {
                    posthog.capture(
                        'posthog ai turn suggestion connect slack clicked',
                        turnSuggestionEventProperties(props, values.suggestion)
                    )
                }
                // The OAuth flow runs in another tab, so the workspace shows up here only through a
                // refetch: the integrations poller plus a reload when this tab becomes visible again.
                actions.startPolling()
                cache.pollingIntegrations = true
                cache.disposables.add(
                    () => {
                        const onVisible = (): void => {
                            if (document.visibilityState === 'visible') {
                                actions.loadIntegrations()
                            }
                        }
                        document.addEventListener('visibilitychange', onVisible)
                        return () => document.removeEventListener('visibilitychange', onVisible)
                    },
                    'slackConnectVisibility',
                    { pauseOnPageHidden: false }
                )
            },
            loadIntegrationsSuccess: ({ integrations }) => {
                if (!values.waitingForSlack) {
                    return
                }
                const workspace = integrations.find((integration) => integration.kind === 'slack')
                if (workspace) {
                    actions.setSlackIntegrationId(workspace.id)
                    stopWaitingForSlack()
                }
            },
            createScoutSuccess: () => {
                stopWaitingForSlack()
            },
            createScoutFailure: ({ error }) => {
                if (values.suggestion) {
                    posthog.capture('posthog ai turn suggestion scout creation failed', {
                        ...turnSuggestionEventProperties(props, values.suggestion),
                        error,
                    })
                }
            },
        }
    }),
    beforeUnmount(({ cache, actions }) => {
        // The poller is refcounted across subscribers, so only a card that started it stops it.
        if (cache.pollingIntegrations) {
            actions.stopPolling()
            cache.pollingIntegrations = false
        }
    }),
])
