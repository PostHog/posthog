/**
 * State and telemetry for the PostHog AI onboarding takeover: which step is showing, what a dismissal
 * persists, and what a chosen starter prompt does. Deliberately host-agnostic — it does not know whether
 * PostHog AI was opened on `/ai` or in the side panel, nor which runtime is active. The host decides when to
 * mount it (see `MaybePhaiOnboarding` in `scenes/max`) and passes the composer's `panelId`.
 *
 * "Seen" is stored per user on the server rather than per device, so the takeover shows exactly once no
 * matter where the user signs in. The replay button re-opens it without clearing that flag.
 */
export const aiOnboardingLogic = kea<aiOnboardingLogicType>([
    path(['products', 'posthog_ai', 'frontend', 'logics', 'aiOnboardingLogic']),
    props({} as AiOnboardingLogicProps),
    key((props) => props.panelId ?? 'scene'),

    connect((props: AiOnboardingLogicProps) => ({
        values: [
            userLogic,
            ['user'],
            teamLogic,
            ['currentTeam'],
            integrationsLogic,
            ['githubIntegrations', 'integrationsLoading'],
            aiConsentLogic,
            ['dataProcessingAccepted'],
        ],
        actions: [userLogic, ['updateUser'], composerSeedLogic({ panelId: props.panelId }), ['setSeed']],
    })),

    actions({
        openOnboarding: (isReplay: boolean = false) => ({ isReplay }),
        closeOnboarding: true,
        finishOnboarding: true,
        setStepIndex: (stepIndex: number) => ({ stepIndex }),
        markStepViewed: (stepKey: string) => ({ stepKey }),
        selectStarterPrompt: (prompt: string) => ({ prompt }),
        clickGithubCta: true,
        replayMedia: true,
        markOnboardingSeen: true,
    }),

    reducers({
        isOpen: [
            false,
            {
                openOnboarding: () => true,
                closeOnboarding: () => false,
                finishOnboarding: () => false,
                selectStarterPrompt: () => false,
            },
        ],
        isReplay: [
            false,
            {
                openOnboarding: (_, { isReplay }) => isReplay,
            },
        ],
        stepIndex: [
            0,
            {
                openOnboarding: () => 0,
                setStepIndex: (_, { stepIndex }) => stepIndex,
            },
        ],
        // The seen flag normally round-trips the server, but an impersonated session can never persist
        // it, so hold it here as well to keep the takeover closed for the rest of the session.
        seenThisSession: [
            false,
            {
                markOnboardingSeen: () => true,
            },
        ],
        // Fire-once guard so re-entering a step (via Back, or the dot row) doesn't re-report it.
        viewedStepKeys: [
            {} as Record<string, true>,
            {
                openOnboarding: () => ({}),
                markStepViewed: (state, { stepKey }) => ({ ...state, [stepKey]: true }),
            },
        ],
    }),

    selectors({
        currentStep: [
            (s) => [s.stepIndex],
            (stepIndex: number): OnboardingStep | null => DEFAULT_ONBOARDING_STEPS[stepIndex] ?? null,
        ],
        hasSeenOnboardingPersisted: [
            (s) => [s.user],
            (user: UserType | null): boolean => !!user?.has_seen_product_intro_for?.[POSTHOG_AI_ONBOARDING_SEEN_KEY],
        ],
        hasSeenOnboarding: [
            (s) => [s.hasSeenOnboardingPersisted, s.seenThisSession],
            (hasSeenOnboardingPersisted: boolean, seenThisSession: boolean): boolean =>
                hasSeenOnboardingPersisted || seenThisSession,
        ],
        // `TeamPublicType` has no `ingested_event`, so read it defensively rather than casting.
        projectHasData: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): boolean =>
                !!currentTeam && 'ingested_event' in currentTeam && !!currentTeam.ingested_event,
        ],
        starterPrompts: [
            (s) => [s.projectHasData],
            (projectHasData: boolean): readonly string[] =>
                projectHasData ? DEFAULT_STARTER_PROMPTS : EMPTY_PROJECT_STARTER_PROMPTS,
        ],
        githubConnected: [
            (s) => [s.githubIntegrations],
            (githubIntegrations: IntegrationType[]): boolean => githubIntegrations.length > 0,
        ],
        repositoryCount: [
            (s) => [s.githubIntegrations],
            (githubIntegrations: IntegrationType[]): number => githubIntegrations.length,
        ],
        reportProperties: [
            (s) => [s.currentStep, s.stepIndex, s.isReplay],
            (currentStep: OnboardingStep | null, stepIndex: number, isReplay: boolean): OnboardingReportProperties => ({
                step_key: currentStep?.key ?? 'unknown',
                step_index: stepIndex,
                step_count: DEFAULT_ONBOARDING_STEPS.length,
                is_replay: isReplay,
            }),
        ],
    }),

    listeners(({ actions, values }) => ({
        openOnboarding: () => {
            posthog.capture('posthog ai onboarding shown', values.reportProperties)
            if (values.currentStep) {
                actions.markStepViewed(values.currentStep.key)
            }
        },
        setStepIndex: () => {
            const step = values.currentStep
            if (!step || values.viewedStepKeys[step.key]) {
                return
            }
            actions.markStepViewed(step.key)
            posthog.capture('posthog ai onboarding step viewed', values.reportProperties)
        },
        closeOnboarding: () => {
            // Which step a user bails on is the segment signal the onboarding research relies on, so the
            // skip event carries the step it happened on rather than only reporting that a dismissal occurred.
            posthog.capture('posthog ai onboarding step skipped', values.reportProperties)
            posthog.capture('posthog ai onboarding dismissed', values.reportProperties)
            actions.markOnboardingSeen()
        },
        finishOnboarding: () => {
            posthog.capture('posthog ai onboarding completed', values.reportProperties)
            actions.markOnboardingSeen()
        },
        selectStarterPrompt: ({ prompt }) => {
            posthog.capture('posthog ai onboarding starter prompt clicked', {
                ...values.reportProperties,
                prompt,
            })
            // Same org-level AI data-processing gate the other seed producers use: without approval the
            // prompt only prefills, so the consent popover never fires on top of the onboarding. The user's
            // own send then goes through the composer's normal consent flow.
            actions.setSeed({ prompt, autoSubmit: values.dataProcessingAccepted })
            actions.markOnboardingSeen()
        },
        clickGithubCta: () => {
            posthog.capture('posthog ai onboarding github cta clicked', {
                ...values.reportProperties,
                github_connected: values.githubConnected,
            })
        },
        replayMedia: () => {
            posthog.capture('posthog ai onboarding media replayed', values.reportProperties)
        },
        markOnboardingSeen: () => {
            // Reads the persisted value, not `hasSeenOnboarding`: the session reducer above already
            // flipped on this action, so the combined selector would skip every write.
            if (values.hasSeenOnboardingPersisted) {
                return
            }
            // `/api/users/` rejects writes from an impersonated session (ImpersonationBlockedPathsMiddleware),
            // and the only outcome of trying is a failure toast on top of the takeover.
            if (values.user?.is_impersonated) {
                return
            }
            actions.updateUser({
                has_seen_product_intro_for: {
                    ...values.user?.has_seen_product_intro_for,
                    [POSTHOG_AI_ONBOARDING_SEEN_KEY]: true,
                },
            })
        },
    })),
])
