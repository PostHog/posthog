export const subscriptionSuggestionLogic: LogicWrapper<subscriptionSuggestionLogicType> =
    kea<subscriptionSuggestionLogicType>([
        props({} as TurnSuggestionLogicProps),
        key((props) => `${props.streamKey}:${props.turnIndex}`),
        path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'subscriptionSuggestionLogic', key]),
        connect((props: TurnSuggestionLogicProps) => ({
            values: [
                turnSuggestionLogic(props),
                ['suggestion as baseSuggestion'],
                slackDestinationLogic(props),
                ['slackIntegrationId', 'slackChannel', 'slackDestinationDisabledReason'],
                projectLogic,
                ['currentProjectId'],
            ],
            actions: [turnSuggestionLogic(props), ['markCompleted']],
        })),
        actions({
            setCadence: (cadence: ScoutSuggestionCadence) => ({ cadence }),
        }),
        loaders(({ values, props }) => ({
            createdSubscription: [
                null as SubscriptionApi | null,
                {
                    createSubscription: async () => {
                        const { suggestion, cadence, slackIntegrationId, slackChannel, currentProjectId } = values
                        if (!suggestion || slackIntegrationId === null || !slackChannel || currentProjectId === null) {
                            return values.createdSubscription
                        }
                        const insightId =
                            suggestion.subscription.insightId ??
                            (await getInsightId(suggestion.subscription.insightShortId as InsightShortId))
                        if (insightId === undefined) {
                            throw new Error('The insight this subscription sends could not be found')
                        }
                        const created = await subscriptionsCreate(
                            String(currentProjectId),
                            buildSubscriptionCreatePayload({
                                suggestion,
                                cadence,
                                insightId,
                                slackIntegrationId,
                                slackChannel,
                            })
                        )
                        posthog.capture('posthog ai turn suggestion subscription created', {
                            ...turnSuggestionEventProperties(props, suggestion),
                            cadence,
                            subscription_id: created.id,
                        })
                        return created
                    },
                },
            ],
        })),
        reducers({
            cadenceOverride: [
                null as ScoutSuggestionCadence | null,
                {
                    setCadence: (_, { cadence }) => cadence,
                },
            ],
            createError: [
                null as string | null,
                {
                    createSubscription: () => null,
                    createSubscriptionFailure: (_, { error }) => error,
                },
            ],
        }),
        selectors({
            suggestion: [
                (s) => [s.baseSuggestion],
                (baseSuggestion: TurnSuggestion | null): SubscriptionTurnSuggestion | null =>
                    baseSuggestion?.kind === 'subscription' ? baseSuggestion : null,
            ],
            cadence: [
                (s) => [s.cadenceOverride, s.suggestion],
                (
                    cadenceOverride: ScoutSuggestionCadence | null,
                    suggestion: SubscriptionTurnSuggestion | null
                ): ScoutSuggestionCadence => cadenceOverride ?? suggestion?.subscription.cadence ?? 'weekly',
            ],
            createDisabledReason: [
                (s) => [s.createdSubscriptionLoading, s.currentProjectId, s.slackDestinationDisabledReason],
                (
                    createdSubscriptionLoading: boolean,
                    currentProjectId: number | null,
                    slackDestinationDisabledReason: string | null
                ): string | null => {
                    if (createdSubscriptionLoading) {
                        return 'Creating the subscription'
                    }
                    if (currentProjectId === null) {
                        return 'Project is still loading'
                    }
                    return slackDestinationDisabledReason
                },
            ],
            subscriptionUrl: [
                (s) => [s.createdSubscription, s.suggestion],
                (
                    createdSubscription: SubscriptionApi | null,
                    suggestion: SubscriptionTurnSuggestion | null
                ): string | null =>
                    createdSubscription && suggestion
                        ? urls.insightSubcription(
                              suggestion.subscription.insightShortId as InsightShortId,
                              String(createdSubscription.id)
                          )
                        : null,
            ],
        }),
        listeners(({ actions, values, props }) => ({
            createSubscriptionSuccess: () => {
                actions.markCompleted()
            },
            createSubscriptionFailure: ({ error }) => {
                if (values.suggestion) {
                    posthog.capture('posthog ai turn suggestion subscription creation failed', {
                        ...turnSuggestionEventProperties(props, values.suggestion),
                        error,
                    })
                }
            },
        })),
    ])
