export const errorAlertSuggestionLogic: LogicWrapper<errorAlertSuggestionLogicType> =
    kea<errorAlertSuggestionLogicType>([
        props({} as TurnSuggestionLogicProps),
        key((props) => `${props.streamKey}:${props.turnIndex}`),
        path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'errorAlertSuggestionLogic', key]),
        connect((props: TurnSuggestionLogicProps) => ({
            values: [
                turnSuggestionLogic(props),
                ['suggestion as baseSuggestion'],
                slackDestinationLogic(props),
                ['slackIntegrationId', 'slackChannel', 'slackDestinationDisabledReason'],
                projectLogic,
                ['currentProjectId'],
            ],
            actions: [turnSuggestionLogic(props), ['markCompleted']],
        })),
        loaders(({ values, props }) => ({
            createdAlert: [
                null as HogFunctionType | null,
                {
                    createAlert: async () => {
                        const { suggestion, slackIntegrationId, slackChannel, currentProjectId } = values
                        if (!suggestion || slackIntegrationId === null || !slackChannel || currentProjectId === null) {
                            return values.createdAlert
                        }
                        const created = await api.hogFunctions.create(
                            buildErrorAlertHogFunctionPayload({ suggestion, slackIntegrationId, slackChannel })
                        )
                        posthog.capture('posthog ai turn suggestion error alert created', {
                            ...turnSuggestionEventProperties(props, suggestion),
                            hog_function_id: created.id,
                        })
                        return created
                    },
                },
            ],
        })),
        reducers({
            createError: [
                null as string | null,
                {
                    createAlert: () => null,
                    createAlertFailure: (_, { error }) => error,
                },
            ],
        }),
        selectors({
            suggestion: [
                (s) => [s.baseSuggestion],
                (baseSuggestion: TurnSuggestion | null): ErrorAlertTurnSuggestion | null =>
                    baseSuggestion?.kind === 'error_alert' ? baseSuggestion : null,
            ],
            createDisabledReason: [
                (s) => [s.createdAlertLoading, s.currentProjectId, s.slackDestinationDisabledReason],
                (
                    createdAlertLoading: boolean,
                    currentProjectId: number | null,
                    slackDestinationDisabledReason: string | null
                ): string | null => {
                    if (createdAlertLoading) {
                        return 'Creating the alert'
                    }
                    if (currentProjectId === null) {
                        return 'Project is still loading'
                    }
                    return slackDestinationDisabledReason
                },
            ],
            alertUrl: [
                (s) => [s.createdAlert],
                (createdAlert: HogFunctionType | null): string | null =>
                    createdAlert ? urls.errorTrackingAlert(createdAlert.id) : null,
            ],
        }),
        listeners(({ actions, values, props }) => ({
            createAlertSuccess: () => {
                actions.markCompleted()
            },
            createAlertFailure: ({ error }) => {
                if (values.suggestion) {
                    posthog.capture('posthog ai turn suggestion error alert creation failed', {
                        ...turnSuggestionEventProperties(props, values.suggestion),
                        error,
                    })
                }
            },
        })),
    ])
