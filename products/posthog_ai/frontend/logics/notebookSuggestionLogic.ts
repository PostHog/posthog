/**
 * State of one notebook suggestion card: the title the user can edit and the save call that writes
 * the conversation so far into a new markdown notebook. Keyed per turn like the scout card.
 */
export const notebookSuggestionLogic: LogicWrapper<notebookSuggestionLogicType> = kea<notebookSuggestionLogicType>([
    props({} as NotebookSuggestionLogicProps),
    key((props) => `${props.streamKey}:${props.turnIndex}`),
    path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'notebookSuggestionLogic', key]),
    connect((props: NotebookSuggestionLogicProps) => ({
        values: [
            runStreamLogic({ streamKey: props.streamKey }),
            ['turnSuggestions', 'threadItems', 'toolInvocations'],
            projectLogic,
            ['currentProjectId'],
        ],
    })),
    actions({
        setTitle: (title: string) => ({ title }),
        dismiss: true,
        reportShown: true,
    }),
    loaders(({ values, props }) => ({
        savedNotebook: [
            null as NotebookApi | null,
            {
                saveNotebook: async () => {
                    const { suggestion, notebookPreview, notebookTitle, currentProjectId } = values
                    if (!suggestion || !notebookPreview || !notebookTitle.trim() || currentProjectId === null) {
                        return values.savedNotebook
                    }
                    const saved = await notebooksCreate(String(currentProjectId), {
                        title: notebookTitle.trim(),
                        content: notebookPreview.content,
                        text_content: notebookPreview.markdown,
                    })
                    posthog.capture('posthog ai turn suggestion notebook saved', {
                        ...turnSuggestionEventProperties(props, suggestion),
                        notebook_short_id: saved.short_id,
                        message_count: notebookPreview.messageCount,
                        query_count: notebookPreview.queryCount,
                    })
                    return saved
                },
            },
        ],
    })),
    reducers({
        titleOverride: [
            null as string | null,
            {
                setTitle: (_, { title }) => title,
            },
        ],
        dismissed: [
            false,
            {
                dismiss: () => true,
            },
        ],
        shownReported: [
            false,
            {
                reportShown: () => true,
            },
        ],
        saveError: [
            null as string | null,
            {
                saveNotebook: () => null,
                saveNotebookFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        suggestion: [
            (s, p) => [s.turnSuggestions, p.turnIndex],
            (turnSuggestions: Record<number, TurnSuggestion>, turnIndex: number): NotebookTurnSuggestion | null => {
                const suggestion = turnSuggestions[turnIndex]
                return suggestion?.kind === 'notebook' ? suggestion : null
            },
        ],
        notebookTitle: [
            (s) => [s.titleOverride, s.suggestion],
            (titleOverride: string | null, suggestion: NotebookTurnSuggestion | null): string =>
                titleOverride ?? suggestion?.notebook.title ?? '',
        ],
        notebookPreview: [
            (s) => [s.suggestion, s.notebookTitle, s.threadItems, s.toolInvocations],
            (
                suggestion: NotebookTurnSuggestion | null,
                notebookTitle: string,
                threadItems: ThreadItem[],
                toolInvocations: Map<string, ToolInvocation>
            ): ConversationNotebook | null =>
                suggestion
                    ? buildConversationNotebook({
                          title: notebookTitle,
                          summary: suggestion.notebook.summary,
                          threadItems,
                          toolInvocations,
                      })
                    : null,
        ],
        saveDisabledReason: [
            (s) => [s.notebookTitle, s.currentProjectId, s.savedNotebookLoading],
            (notebookTitle: string, currentProjectId: number | null, savedNotebookLoading: boolean): string | null => {
                if (savedNotebookLoading) {
                    return 'Saving the notebook'
                }
                if (currentProjectId === null) {
                    return 'Project is still loading'
                }
                if (!notebookTitle.trim()) {
                    return 'Give the notebook a title first'
                }
                return null
            },
        ],
        notebookUrl: [
            (s) => [s.savedNotebook],
            (savedNotebook: NotebookApi | null): string | null =>
                savedNotebook ? urls.notebook(savedNotebook.short_id) : null,
        ],
    }),
    listeners(({ values, props }) => ({
        reportShown: () => {
            if (values.suggestion) {
                posthog.capture(
                    'posthog ai turn suggestion shown',
                    turnSuggestionEventProperties(props, values.suggestion)
                )
            }
        },
        dismiss: () => {
            if (values.suggestion) {
                posthog.capture(
                    'posthog ai turn suggestion dismissed',
                    turnSuggestionEventProperties(props, values.suggestion)
                )
            }
        },
        saveNotebookFailure: ({ error }) => {
            if (values.suggestion) {
                posthog.capture('posthog ai turn suggestion notebook save failed', {
                    ...turnSuggestionEventProperties(props, values.suggestion),
                    error,
                })
            }
        },
    })),
])
