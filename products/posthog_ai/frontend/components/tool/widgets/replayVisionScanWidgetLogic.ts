import { MakeLogicType, afterMount, kea, key, listeners, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { visionScannersObservationsList } from 'products/replay_vision/frontend/generated/api'
import type { ReplayObservationApi } from 'products/replay_vision/frontend/generated/api.schemas'
import {
    OBSERVE_POLL_GRACE_MS,
    scheduleObservationPoll,
    shouldPollObservations,
} from 'products/replay_vision/frontend/logics/observationPolling'

export interface ReplayVisionScanWidgetLogicProps {
    /** The inline scanner the scan minted. Its observations are the scan's results. */
    scanId: string
    /** Only these sessions belong to this scan; the scanner is shared and holds older rows too. */
    sessionIds: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayVisionScanWidgetLogicValues {
    observations: ReplayObservationApi[]
    observationsLoading: boolean
    pendingCount: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayVisionScanWidgetLogicActions {
    loadObservations: () => any
    loadObservationsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadObservationsSuccess: (
        observations: ReplayObservationApi[],
        payload?: any
    ) => {
        observations: ReplayObservationApi[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayVisionScanWidgetLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        pendingCount: (observations: any, arg: string[]) => number
    }
}

export type replayVisionScanWidgetLogicType = MakeLogicType<
    replayVisionScanWidgetLogicValues,
    replayVisionScanWidgetLogicActions,
    ReplayVisionScanWidgetLogicProps,
    replayVisionScanWidgetLogicMeta
>

export const replayVisionScanWidgetLogic = kea<replayVisionScanWidgetLogicType>([
    path(['products', 'posthog_ai', 'frontend', 'components', 'tool', 'widgets', 'replayVisionScanWidgetLogic']),
    props({} as ReplayVisionScanWidgetLogicProps),
    key((props: ReplayVisionScanWidgetLogicProps) => `${props.scanId}:${props.sessionIds.join(',')}`),

    loaders(({ props }) => ({
        observations: [
            [] as ReplayObservationApi[],
            {
                loadObservations: async () => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        return []
                    }
                    const response = await visionScannersObservationsList(String(teamId), props.scanId, {
                        limit: props.sessionIds.length,
                    })
                    const wanted = new Set(props.sessionIds)
                    return (response.results ?? []).filter((o) => wanted.has(o.session_id))
                },
            },
        ],
    })),

    selectors({
        pendingCount: [
            (s) => [s.observations, (_, p: ReplayVisionScanWidgetLogicProps) => p.sessionIds],
            (observations: ReplayObservationApi[], sessionIds: string[]): number =>
                sessionIds.length - observations.filter((o) => o.status !== 'pending' && o.status !== 'running').length,
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        loadObservationsSuccess: () => {
            // A row appears a moment after its scan starts, so an empty response early on means "not yet"
            // rather than "nothing to wait for". The grace window covers that gap.
            scheduleObservationPoll(
                cache.disposables,
                shouldPollObservations(values.pendingCount > 0, cache.startedAt + OBSERVE_POLL_GRACE_MS),
                actions.loadObservations
            )
        },
    })),

    afterMount(({ actions, cache }) => {
        cache.startedAt = Date.now()
        actions.loadObservations()
    }),
])
