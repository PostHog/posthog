import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { visionScannersObservationsList } from 'products/replay_vision/frontend/generated/api'
import type { ReplayObservationApi } from 'products/replay_vision/frontend/generated/api.schemas'
import {
    OBSERVE_POLL_GRACE_MS,
    scheduleObservationPoll,
    shouldPollObservations,
} from 'products/replay_vision/frontend/logics/observationPolling'

/**
 * A scan takes at most MAX_SESSIONS_PER_SCAN (200) recordings and a session can hold more than one row,
 * so the default page would truncate a large scan and leave sessions looking unfinished forever.
 */
const OBSERVATIONS_PAGE_LIMIT = 500
/** Give up after this long. A recording that has not settled by now needs the scanner page, not a spinner. */
const POLL_DEADLINE_MS = 10 * 60 * 1000
/** Consecutive failed reads before the widget stops retrying. */
const MAX_CONSECUTIVE_FAILURES = 5

export interface ReplayVisionScanWidgetLogicProps {
    /** The inline scanner the scan minted. Its observations are the scan's results. */
    scanId: string
    /** Only these sessions belong to this scan; the scanner is shared and holds older rows too. */
    sessionIds: string[]
}

