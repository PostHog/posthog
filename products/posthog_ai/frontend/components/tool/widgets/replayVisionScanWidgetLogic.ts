export interface replayVisionScanWidgetLogicValues {
    gaveUp: boolean
    latestPerSession: ReplayObservationApi[]
    observations: ReplayObservationApi[]
    observationsLoading: boolean
    pendingCount: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayVisionScanWidgetLogicActions {
    giveUp: () => {
        value: true
    }
    loadObservations: () => any
    loadObservationsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadObservationsSuccess: (
        observations: ReplayObservationApi[],
        payload?: any
    ) => {
        observations: ReplayObservationApi[]
        payload?: any
    }
}

