export const taskShareLogic = kea<taskShareLogicType>([
    path((key) => ['products', 'posthog_ai', 'frontend', 'scenes', 'TaskTracker', 'taskShareLogic', key]),
    props({} as TaskShareLogicProps),
    key((props) => props.taskId),

    connect(() => ({
        values: [projectLogic, ['currentProjectId'], userLogic, ['user']],
    })),

    actions({
        openShareDialog: true,
        closeShareDialog: true,
        setVisibility: (visibility: 'private' | 'public') => ({ visibility }),
        moveToSpace: (spaceId: string, previousSpaceId: string | null, visibility: 'private' | 'public' | null) => ({
            spaceId,
            previousSpaceId,
            visibility,
        }),
        channelChanged: (channel: string | null) => ({ channel }),
        visibilityChanged: true,
        copyLink: true,
    }),

    loaders(({ props, values }) => ({
        shareState: [
            EMPTY_STATE,
            {
                loadShareState: async () => {
                    const projectId = String(values.currentProjectId)
                    const [task, spaces] = await Promise.all([
                        tasksRetrieve(projectId, props.taskId),
                        loadSpaces(projectId),
                    ])
                    return { channel: task.channel ?? null, creatorUuid: task.created_by?.uuid ?? null, spaces }
                },
            },
        ],
    })),

    reducers({
        shareState: {
            channelChanged: (state, { channel }) => ({ ...state, channel }),
        },
        shareDialogOpen: [
            false,
            {
                openShareDialog: () => true,
                closeShareDialog: () => false,
                visibilityChanged: () => false,
            },
        ],
        visibilityChanging: [
            false,
            {
                setVisibility: () => true,
                moveToSpace: () => true,
                visibilityChanged: () => false,
            },
        ],
    }),

    selectors({
        visibility: [
            (s) => [s.shareState],
            (shareState): TaskVisibility | null => {
                const space = shareState.spaces.find((space: TaskSpace) => space.id === shareState.channel)
                return space ? spaceVisibility(space) : null
            },
        ],
        isCreator: [
            (s) => [s.shareState, s.user],
            (shareState, user): boolean => !!shareState.creatorUuid && shareState.creatorUuid === user?.uuid,
        ],
    }),

    listeners(({ actions, values, props }) => ({
        setVisibility: ({ visibility }) => {
            const role = visibility === 'private' ? 'personal' : 'general'
            const target = values.shareState.spaces.find((space) => space.system_role === role)
            if (!target) {
                toast.error({ title: `Could not make the task ${visibility}`, description: 'Try again.' })
                actions.visibilityChanged()
                return
            }
            actions.moveToSpace(target.id, values.shareState.channel, visibility)
        },
        moveToSpace: async ({ spaceId, previousSpaceId, visibility }) => {
            try {
                const updated = await tasksPartialUpdate(String(values.currentProjectId), props.taskId, {
                    channel: spaceId,
                })
                actions.channelChanged(updated.channel ?? null)
                posthog.capture('task visibility changed', { task_id: props.taskId, visibility: visibility ?? 'undo' })
                if (visibility === 'public') {
                    await copyToClipboard(taskLink(props.taskId), 'task link', { silent: true })
                }
                if (!visibility) {
                    toast.success({ title: 'The change is undone' })
                    return
                }
                toast.success({
                    title:
                        visibility === 'public'
                            ? 'The task is public. Paste the link to share it.'
                            : 'The task is private',
                    action: previousSpaceId
                        ? { label: 'Undo', onClick: () => actions.moveToSpace(previousSpaceId, null, null) }
                        : undefined,
                })
            } catch {
                toast.error({
                    title: visibility ? `Could not make the task ${visibility}` : 'Could not undo the change',
                    description: 'Try again.',
                })
            } finally {
                actions.visibilityChanged()
            }
        },
        copyLink: async () => {
            await copyToClipboard(taskLink(props.taskId), 'task link')
        },
    })),

    afterMount(({ actions }) => {
        actions.loadShareState()
    }),
])
