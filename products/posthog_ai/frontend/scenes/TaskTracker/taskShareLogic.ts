export type TaskVisibility = 'private' | 'public' | 'shared'
export type TaskSpace = Pick<ChannelDTOApi, 'id' | 'system_role' | 'channel_type'>

export interface TaskShareLogicProps {
    taskId: string
}

export interface TaskShareState {
    channel: string | null
    creatorUuid: string | null
    originProduct: string | null
    spaces: TaskSpace[]
}

// Mirrors products/tasks/backend/visibility.py. Slack tasks in a shared thread are readable by
// the team whatever their space, so the space cannot make them private.
const SPACE_INDEPENDENT_ORIGIN_PRODUCTS = new Set(['slack'])
// Tasks from these origins stay team readable while they have no space.
const TEAM_READABLE_ORIGIN_PRODUCTS = new Set([
    'signal_report',
    'signals_scout',
    'onboarding',
    'hogdesk',
    'workflow',
    'experiments',
])

export function taskVisibility(shareState: TaskShareState): TaskVisibility | null {
    if (!shareState.spaces.length || SPACE_INDEPENDENT_ORIGIN_PRODUCTS.has(shareState.originProduct ?? '')) {
        return null
    }
    if (!shareState.channel) {
        const teamReadable =
            !shareState.creatorUuid || TEAM_READABLE_ORIGIN_PRODUCTS.has(shareState.originProduct ?? '')
        return teamReadable ? 'public' : 'private'
    }
    const space = shareState.spaces.find((space) => space.id === shareState.channel)
    return space ? spaceVisibility(space) : null
}

export function spaceVisibility(space: Pick<TaskSpace, 'system_role' | 'channel_type'>): TaskVisibility {
    if (space.system_role === 'personal' || space.channel_type === 'personal') {
        return 'private'
    }
    return space.channel_type === 'private' ? 'shared' : 'public'
}

function toSpaces(response: ChannelListResponseApi): TaskSpace[] {
    const rows = Array.isArray(response) ? response : response.results
    return rows.map((row) => ({
        id: String(row.id),
        system_role: row.system_role ?? null,
        channel_type: row.channel_type ?? '',
    }))
}

async function loadSpaces(projectId: string): Promise<TaskSpace[]> {
    const spaces = toSpaces(await taskChannelsList(projectId))
    const hasDefaults = ['personal', 'general'].every((role) => spaces.some((space) => space.system_role === role))
    if (hasDefaults) {
        return spaces
    }
    return toSpaces((await taskChannelsProvisionDefaultsCreate(projectId)).channels)
}

function taskLink(taskId: string): string {
    // The project in the path opens this task for someone whose current project differs.
    return urls.absolute(urls.currentProject(urls.aiTask(taskId)))
}

// Undo runs outside the logic so it still works after the person leaves the task.
async function undoMove(projectId: string, taskId: string, previousSpaceId: string): Promise<void> {
    try {
        const updated = await tasksPartialUpdate(projectId, taskId, { channel: previousSpaceId })
        taskShareLogic.findMounted({ taskId })?.actions.channelChanged(updated.channel ?? null)
        posthog.capture('task visibility changed', { task_id: taskId, visibility: 'undo' })
        toast.success({ title: 'The change is undone' })
    } catch {
        toast.error({ title: 'Could not undo the change', description: 'Try again.' })
    }
}

