/** The download-by-id URL redirects to a fresh presigned link, so an `img` or an `a` can use it directly. */
export function artifactDownloadUrl(
    projectId: number | null,
    run: TaskRunDetailDTOApi | null,
    artifact: TaskRunArtifactResponseApi
): string | null {
    if (projectId === null || !run || !artifact.id) {
        return null
    }
    return getTasksRunsArtifactsDownloadRetrieveUrl(String(projectId), run.task, run.id, artifact.id)
}

export const taskRunArtifactsLogic = kea<taskRunArtifactsLogicType>([
    props({} as TaskRunArtifactsLogicProps),
    key((props) => props.taskId),
    path((key) => ['products', 'posthog_ai', 'frontend', 'scenes', 'TaskTracker', 'taskRunArtifactsLogic', key]),
    connect((props: TaskRunArtifactsLogicProps) => ({
        values: [taskDetailSceneLogic({ taskId: props.taskId }), ['selectedRun'], projectLogic, ['currentProjectId']],
    })),
    actions({
        setActiveTab: (tab: TaskRunTab) => ({ tab }),
        selectArtifact: (artifactId: string) => ({ artifactId }),
        stepArtifact: (delta: number) => ({ delta }),
        downloadArtifact: (artifact: TaskRunArtifactResponseApi) => ({ artifact }),
        ensureSelectedText: true,
    }),
    loaders(({ values }) => ({
        artifactText: [
            null as ArtifactText | null,
            {
                loadArtifactText: async (artifact: TaskRunArtifactResponseApi): Promise<ArtifactText | null> => {
                    const run = values.selectedRun
                    if (values.currentProjectId === null || !run || !artifact.id || !artifact.storage_path) {
                        return null
                    }
                    // The POST download streams the bytes from the app origin, so reading them needs no CORS
                    // grant on the bucket. The GET variant redirects to object storage instead.
                    try {
                        // nosemgrep: prefer-codegen-api -- A file download: the generated function parses the body as JSON.
                        const response = await api.createResponse(
                            getTasksRunsArtifactsDownloadCreateUrl(String(values.currentProjectId), run.task, run.id),
                            { storage_path: artifact.storage_path }
                        )
                        return { artifactId: artifact.id, text: await response.text(), error: null }
                    } catch {
                        return {
                            artifactId: artifact.id,
                            text: null,
                            error: 'This file did not load. Try again later.',
                        }
                    }
                },
            },
        ],
    })),
    reducers({
        activeTab: ['conversation' as TaskRunTab, { setActiveTab: (_, { tab }) => tab }],
        selectedArtifactId: [null as string | null, { selectArtifact: (_, { artifactId }) => artifactId }],
        textsById: [
            {} as Record<string, ArtifactText>,
            {
                loadArtifactTextSuccess: (state, { artifactText }) =>
                    artifactText ? { ...state, [artifactText.artifactId]: artifactText } : state,
            },
        ],
    }),
    selectors({
        artifacts: [
            (s) => [s.selectedRun],
            (selectedRun: TaskRunDetailDTOApi | null): TaskRunArtifactResponseApi[] =>
                visibleRunArtifacts(selectedRun?.artifacts ?? []),
        ],
        selectedIndex: [
            (s) => [s.artifacts, s.selectedArtifactId],
            (artifacts: TaskRunArtifactResponseApi[], selectedArtifactId: string | null): number =>
                Math.max(
                    0,
                    artifacts.findIndex((artifact) => artifact.id === selectedArtifactId)
                ),
        ],
        selectedArtifact: [
            (s) => [s.artifacts, s.selectedIndex],
            (artifacts: TaskRunArtifactResponseApi[], selectedIndex: number): TaskRunArtifactResponseApi | null =>
                artifacts[selectedIndex] ?? null,
        ],
        selectedKind: [
            (s) => [s.selectedArtifact],
            (selectedArtifact: TaskRunArtifactResponseApi | null): ArtifactPreviewKind | null =>
                selectedArtifact ? artifactPreviewKind(selectedArtifact) : null,
        ],
        selectedText: [
            (s) => [s.selectedArtifact, s.textsById],
            (
                selectedArtifact: TaskRunArtifactResponseApi | null,
                textsById: Record<string, ArtifactText>
            ): ArtifactText | null => (selectedArtifact?.id && textsById[selectedArtifact.id]) || null,
        ],
    }),
    listeners(({ actions, values }) => {
        const loadSelectedText = (): void => {
            const artifact = values.selectedArtifact
            const kind = values.selectedKind
            if (values.activeTab === 'artifacts' && artifact && kind && isTextPreview(kind) && !values.selectedText) {
                actions.loadArtifactText(artifact)
            }
        }
        const previewSelected = (): void => {
            const artifact = values.selectedArtifact
            if (values.activeTab !== 'artifacts' || !artifact || !values.selectedKind) {
                return
            }
            // pinned: analytics event name and properties. Renaming them breaks insights.
            posthog.capture('task artifact previewed', {
                kind: values.selectedKind,
                content_type: artifact.content_type ?? null,
            })
        }
        return {
            setActiveTab: ({ tab }) => {
                if (tab === 'artifacts') {
                    posthog.capture('task artifacts tab opened', { artifact_count: values.artifacts.length })
                }
                previewSelected()
            },
            selectArtifact: previewSelected,
            ensureSelectedText: loadSelectedText,
            stepArtifact: ({ delta }) => {
                const { artifacts, selectedIndex } = values
                const next = artifacts[(selectedIndex + delta + artifacts.length) % artifacts.length]
                if (next?.id) {
                    actions.selectArtifact(next.id)
                }
            },
            downloadArtifact: ({ artifact }) => {
                posthog.capture('task artifact downloaded', { kind: artifactPreviewKind(artifact) })
            },
        }
    }),
])
