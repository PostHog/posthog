/**
 * Comment threads on one artifact version: comments on the whole file, pins on an image, and comments on a
 * text selection. The rows are the ones PostHog Desktop reads and writes.
 */
export const taskArtifactCommentsLogic = kea<taskArtifactCommentsLogicType>([
    props({} as TaskArtifactCommentsLogicProps),
    key((props) => `${props.taskId}:${props.artifactId}`),
    path((key) => ['products', 'posthog_ai', 'frontend', 'scenes', 'TaskTracker', 'taskArtifactCommentsLogic', key]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        setDraft: (target: CommentTarget, draft: string) => ({ target, draft }),
        setPinMode: (pinMode: boolean) => ({ pinMode }),
        setPendingAnchor: (anchor: TextCommentAnchor | RegionCommentAnchor, position: PendingPosition | null) => ({
            anchor,
            position,
        }),
        dismissPending: true,
        submitComment: (target: 'document' | 'pending') => ({ target }),
        replyToThread: (rootId: string) => ({ rootId }),
        setThreadResolved: (rootId: string, resolved: boolean) => ({ rootId, resolved }),
        /** The write for `target` ended. `target` is null when it failed. */
        writeFinished: (target: CommentTarget | null) => ({ target }),
        activateThread: (id: string | null, source: ArtifactThreadSource = 'preview') => ({ id, source }),
        setShowResolved: (showResolved: boolean) => ({ showResolved }),
    }),
    loaders(({ props, values }) => ({
        comments: [
            null as CommentApi[] | null,
            {
                loadComments: async () =>
                    values.currentProjectId === null
                        ? values.comments
                        : await loadAllArtifactComments(
                              String(values.currentProjectId),
                              props.taskId,
                              props.artifactId
                          ),
            },
        ],
    })),
    reducers({
        // Unsent text stays when a write fails, so the person can send it again.
        drafts: [
            {} as Record<CommentTarget, string>,
            {
                setDraft: (state, { target, draft }) => ({ ...state, [target]: draft }),
                dismissPending: ({ pending: _pending, ...rest }) => rest,
                writeFinished: (state, { target }) => {
                    if (!target || !(target in state)) {
                        return state
                    }
                    const { [target]: _sent, ...rest } = state
                    return rest
                },
            },
        ],
        pinMode: [
            false,
            {
                setPinMode: (_, { pinMode }) => pinMode,
                writeFinished: (state, { target }) => (target === 'pending' ? false : state),
            },
        ],
        pendingAnchor: [
            null as TextCommentAnchor | RegionCommentAnchor | null,
            {
                setPendingAnchor: (_, { anchor }) => anchor,
                dismissPending: () => null,
                activateThread: (state, { id }) => (id ? null : state),
                setPinMode: (state, { pinMode }) => (pinMode ? state : null),
                writeFinished: (state, { target }) => (target === 'pending' ? null : state),
            },
        ],
        pendingPosition: [
            null as PendingPosition | null,
            {
                setPendingAnchor: (_, { position }) => position,
                dismissPending: () => null,
                writeFinished: (state, { target }) => (target === 'pending' ? null : state),
            },
        ],
        // What is being written: "document", "pending", or a root id for a reply or a resolve.
        writing: [
            null as CommentTarget | null,
            {
                submitComment: (_, { target }) => target,
                replyToThread: (_, { rootId }) => rootId,
                setThreadResolved: (_, { rootId }) => rootId,
                writeFinished: () => null,
            },
        ],
        activeThreadId: [
            null as string | null,
            {
                activateThread: (_, { id }) => id,
                setPendingAnchor: () => null,
                setPinMode: (state, { pinMode }) => (pinMode ? null : state),
            },
        ],
        showResolved: [false, { setShowResolved: (_, { showResolved }) => showResolved }],
        commentsLoadFailed: [false, { loadCommentsSuccess: () => false, loadCommentsFailure: () => true }],
    }),
    selectors({
        threads: [
            (s) => [s.comments],
            (comments: CommentApi[] | null): ArtifactCommentThread[] | null =>
                comments ? buildArtifactCommentThreads(comments) : null,
        ],
        /** Oldest thread first, like PostHog Desktop, so pins list in number order. Resolved threads show only when asked for. */
        visibleThreads: [
            (s) => [s.threads, s.showResolved],
            (threads: ArtifactCommentThread[] | null, showResolved: boolean): ArtifactCommentThread[] | null =>
                threads ? threads.filter((thread) => showResolved || !thread.resolved) : null,
        ],
        openCount: [
            (s) => [s.threads],
            (threads: ArtifactCommentThread[] | null): number =>
                threads?.filter((thread) => !thread.resolved).length ?? 0,
        ],
        resolvedCount: [
            (s) => [s.threads],
            (threads: ArtifactCommentThread[] | null): number =>
                threads?.filter((thread) => thread.resolved).length ?? 0,
        ],
        /** Threads drawn on the preview: the open ones, and a resolved one while it is the active thread. */
        anchoredThreads: [
            (s) => [s.threads, s.activeThreadId],
            (threads: ArtifactCommentThread[] | null, activeThreadId: string | null): ArtifactCommentThread[] =>
                (threads ?? []).filter((thread) => !thread.resolved || thread.root.id === activeThreadId),
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        const schedulePoll = (): void => {
            cache.disposables.add(() => {
                const id = setTimeout(() => actions.loadComments(), COMMENTS_POLL_INTERVAL_MS)
                return () => clearTimeout(id)
            }, 'commentsPoll')
        }
        const write = async (target: CommentTarget, data: Partial<CommentApi>): Promise<CommentApi | null> => {
            if (values.currentProjectId === null) {
                actions.writeFinished(null)
                return null
            }
            try {
                const saved = await commentsCreate(String(values.currentProjectId), {
                    scope: ARTIFACT_COMMENT_SCOPE,
                    item_id: props.artifactId,
                    is_task: false,
                    mentions: [],
                    ...data,
                })
                actions.loadComments()
                actions.writeFinished(target)
                return saved
            } catch {
                lemonToast.error("Couldn't save the comment. Try again in a moment.")
                actions.writeFinished(null)
                return null
            }
        }
        return {
            setPendingAnchor: ({ anchor }) => {
                // pinned: analytics event name and properties. Renaming them breaks insights.
                posthog.capture('task artifact comment started', {
                    anchor_kind: anchorKindLabel(anchor),
                    kind: props.kind,
                })
            },
            submitComment: async ({ target }) => {
                const content = (values.drafts[target] ?? '').trim()
                const anchor: ArtifactCommentAnchor | null =
                    target === 'document' ? { kind: 'document' } : values.pendingAnchor
                if (!content || !anchor) {
                    actions.writeFinished(null)
                    return
                }
                // The server cannot find the task from an artifact id, so the task rides along in the context.
                const saved = await write(target, { content, item_context: { anchor, taskId: props.taskId } })
                if (saved) {
                    // pinned: analytics event name and properties. Renaming them breaks insights.
                    posthog.capture('task artifact comment added', {
                        anchor_kind: anchorKindLabel(anchor),
                        kind: props.kind,
                    })
                    if (target === 'pending') {
                        window.getSelection()?.removeAllRanges()
                        actions.activateThread(saved.id, 'created')
                    }
                }
            },
            replyToThread: async ({ rootId }) => {
                const content = (values.drafts[rootId] ?? '').trim()
                if (!content) {
                    actions.writeFinished(null)
                    return
                }
                const saved = await write(rootId, {
                    content,
                    source_comment: rootId,
                    item_context: { taskId: props.taskId },
                })
                if (saved) {
                    // pinned: analytics event name and properties. Renaming them breaks insights.
                    posthog.capture('task artifact comment replied', { kind: props.kind })
                }
            },
            setThreadResolved: async ({ rootId, resolved }) => {
                const thread = values.threads?.find((candidate) => candidate.root.id === rootId)
                if (!thread) {
                    actions.writeFinished(null)
                    return
                }
                const rootContext =
                    thread.root.item_context && typeof thread.root.item_context === 'object'
                        ? (thread.root.item_context as Record<string, unknown>)
                        : {}
                // Resolution is a reply that carries the thread state, the same write that Desktop makes.
                const saved = await write(rootId, {
                    content: resolved ? 'Resolved this thread' : 'Reopened this thread',
                    source_comment: rootId,
                    item_context: { ...rootContext, taskId: props.taskId, threadState: resolved ? 'resolved' : 'open' },
                })
                if (saved) {
                    // pinned: analytics event name and properties. Renaming them breaks insights.
                    posthog.capture('task artifact comment resolved', {
                        resolved,
                        anchor_kind: anchorKindLabel(thread.anchor),
                        kind: props.kind,
                    })
                }
            },
            activateThread: ({ id, source }) => {
                const thread = id ? values.threads?.find((candidate) => candidate.root.id === id) : null
                if (thread && source !== 'created') {
                    posthog.capture('task artifact comment thread opened', {
                        anchor_kind: anchorKindLabel(thread.anchor),
                        kind: props.kind,
                        source,
                    })
                }
            },
            loadCommentsSuccess: () => schedulePoll(),
            loadCommentsFailure: () => schedulePoll(),
        }
    }),
    afterMount(({ actions }) => {
        actions.loadComments()
    }),
])
