const COMMENTS_POLL_INTERVAL_MS = 10_000
// The comments list pages at 100. This many pages covers any real artifact, the same cap as Desktop.
const MAX_COMMENT_PAGES = 50

export interface TaskArtifactCommentsLogicProps {
    taskId: string
    /** The artifact version id. Each version has its own threads, the same as in Desktop. */
    artifactId: string
    kind: ArtifactPreviewKind
}

/** What a draft or a write is for: a new comment on the whole file, the pending pin or selection, or a thread. */
export type CommentTarget = 'document' | 'pending' | string

export type ArtifactThreadSource = 'preview' | 'menu' | 'created'

/** Where the pending selection composer sits, in pixels inside the scroll content of the preview. */
export interface PendingPosition {
    left: number
    top: number
}

async function loadAllArtifactComments(projectId: string, taskId: string, artifactId: string): Promise<CommentApi[]> {
    const comments: CommentApi[] = []
    let cursor: string | undefined
    for (let index = 0; index < MAX_COMMENT_PAGES; index++) {
        const page = await commentsList(projectId, {
            scope: ARTIFACT_COMMENT_SCOPE,
            item_id: artifactId,
            task_id: taskId,
            cursor,
        })
        comments.push(...page.results)
        cursor = page.next
            ? (new URL(page.next, window.location.origin).searchParams.get('cursor') ?? undefined)
            : undefined
        if (!cursor) {
            break
        }
    }
    return comments
}

