import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'

import { mlInferenceDecisionsDecideCreate } from './generated/api'
import type { DecideRequestApi, DecideResponseApi } from './generated/api.schemas'

export type PlaygroundQuestionType = 'noul' | 'choice' | 'score'

export interface PlaygroundQuestion {
    id: string
    type: PlaygroundQuestionType
    instructions: string
    /** One option per line as `name: what it means`; only read for choice and score questions. */
    criteria: string
}

export const EXAMPLE_STATE =
    'Hi, I was charged twice for my invoice this month and I need the duplicate refunded today, ' +
    'my accountant is closing the books tomorrow.'

export const EXAMPLE_QUESTIONS: PlaygroundQuestion[] = [
    { id: 'urgent', type: 'noul', instructions: 'Is this urgent?', criteria: '' },
    {
        id: 'queue',
        type: 'choice',
        instructions: 'Which team should handle this?',
        criteria: 'billing: payments, invoices, refunds\nsupport: product questions and bugs',
    },
]

export function parseCriteria(criteria: string): Record<string, string> | undefined {
    const entries = criteria
        .split('\n')
        .map((line) => line.trim())
        .filter(Boolean)
        .map((line): [string, string] => {
            const separator = line.indexOf(':')
            return separator === -1
                ? [line, line]
                : [line.slice(0, separator).trim(), line.slice(separator + 1).trim() || line.slice(0, separator).trim()]
        })
    return entries.length > 0 ? Object.fromEntries(entries) : undefined
}

export function buildDecideRequest(state: string, questions: PlaygroundQuestion[]): DecideRequestApi {
    return {
        state,
        questions: Object.fromEntries(
            questions.map((question) => [
                question.id,
                {
                    type: question.type,
                    instructions: question.instructions,
                    ...(question.type === 'noul' ? {} : { criteria: parseCriteria(question.criteria) }),
                },
            ])
        ),
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface decisionPlaygroundLogicValues {
    currentTeamId: number | null // teamLogic
    askDisabledReason: string | null
    decision: DecideResponseApi | null
    decisionLoading: boolean
    questions: PlaygroundQuestion[]
    requestBody: DecideRequestApi
    state: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface decisionPlaygroundLogicActions {
    addQuestion: () => {
        value: true
    }
    askDecision: () => any
    askDecisionFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    askDecisionSuccess: (
        decision: DecideResponseApi,
        payload?: any
    ) => {
        decision: DecideResponseApi
        payload?: any
    }
    removeQuestion: (id: string) => {
        id: string
    }
    setState: (state: string) => {
        state: string
    }
    updateQuestion: (
        id: string,
        patch: Partial<PlaygroundQuestion>
    ) => {
        id: string
        patch: Partial<PlaygroundQuestion>
    }
}

export type decisionPlaygroundLogicType = MakeLogicType<decisionPlaygroundLogicValues, decisionPlaygroundLogicActions>

export const decisionPlaygroundLogic = kea<decisionPlaygroundLogicType>([
    path(['products', 'ml_inference', 'frontend', 'decisionPlaygroundLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        setState: (state: string) => ({ state }),
        addQuestion: true,
        removeQuestion: (id: string) => ({ id }),
        updateQuestion: (id: string, patch: Partial<PlaygroundQuestion>) => ({ id, patch }),
    }),
    loaders(({ values }) => ({
        decision: [
            null as DecideResponseApi | null,
            {
                askDecision: async () => {
                    if (values.currentTeamId === null) {
                        throw new Error('No project selected')
                    }
                    return await mlInferenceDecisionsDecideCreate(String(values.currentTeamId), values.requestBody)
                },
            },
        ],
    })),
    reducers({
        state: [EXAMPLE_STATE, { setState: (_, { state }) => state }],
        questions: [
            EXAMPLE_QUESTIONS,
            {
                addQuestion: (questions) => [
                    ...questions,
                    { id: `question_${questions.length + 1}`, type: 'noul' as const, instructions: '', criteria: '' },
                ],
                removeQuestion: (questions, { id }) => questions.filter((question) => question.id !== id),
                updateQuestion: (questions, { id, patch }) =>
                    questions.map((question) => (question.id === id ? { ...question, ...patch } : question)),
            },
        ],
    }),
    selectors({
        requestBody: [
            (s) => [s.state, s.questions],
            (state: string, questions: PlaygroundQuestion[]): DecideRequestApi => buildDecideRequest(state, questions),
        ],
        askDisabledReason: [
            (s) => [s.state, s.questions, s.decisionLoading],
            (state: string, questions: PlaygroundQuestion[], decisionLoading: boolean): string | null => {
                if (decisionLoading) {
                    return 'Asking the model'
                }
                if (!state.trim()) {
                    return 'Enter some text to ask about'
                }
                if (questions.length === 0) {
                    return 'Add at least one question'
                }
                if (questions.some((question) => !question.id.trim() || !question.instructions.trim())) {
                    return 'Every question needs an id and instructions'
                }
                if (new Set(questions.map((question) => question.id)).size !== questions.length) {
                    return 'Question ids must be unique'
                }
                return null
            },
        ],
    }),
    listeners({
        askDecisionFailure: ({ error }) => {
            lemonToast.error(error || 'The decision model could not answer. Try again in a moment.')
        },
    }),
])
