import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { mlInferenceDecisionsDecideCreate } from './generated/api'
import type { DecideRequestApi, DecideResponseApi, DecisionAnswerApi } from './generated/api.schemas'

export const ANSWER_QUESTION_ID = 'answer'
// Long enough for one full shake, so a fast answer still gets its moment.
export const MIN_SHAKE_MS = 1200

// The decision model answers with one letter per option, so a question takes at most MAX_OPTIONS_PER_QUESTION (16).
// The classic ball has 20 answers; these 16 keep an 8 yes, 4 unsure, 4 no split.
export const EIGHT_BALL_ANSWERS: Record<string, string> = {
    'It is certain': 'a confident, unqualified yes',
    'Without a doubt': 'a confident yes',
    'Yes definitely': 'a clear yes',
    'As I see it, yes': 'a yes, with a little hedging',
    'Most likely': 'probably yes',
    'Outlook good': 'things look promising',
    Yes: 'a plain yes',
    'Signs point to yes': 'the evidence leans yes',
    'Reply hazy, try again': 'the question is too vague to answer',
    'Ask again later': 'it is too early to tell',
    'Better not tell you now': 'the answer would spoil the surprise',
    'Cannot predict now': 'the outcome is genuinely uncertain',
    "Don't count on it": 'probably not',
    'My reply is no': 'a clear no',
    'Outlook not so good': 'things look unpromising',
    'Very doubtful': 'very unlikely',
}

export function buildEightBallRequest(question: string): DecideRequestApi {
    return {
        state: question.trim(),
        questions: {
            [ANSWER_QUESTION_ID]: {
                type: 'choice',
                instructions:
                    'You are a Magic 8 Ball. Someone asked you the product question above. Which answer would you give?',
                criteria: EIGHT_BALL_ANSWERS,
            },
        },
    }
}

/** iOS Safari only fires devicemotion after this is granted from a tap. */
type MotionPermissionRequest = { requestPermission?: () => Promise<'granted' | 'denied'> }

function motionNeedsPermission(): boolean {
    return (
        typeof DeviceMotionEvent !== 'undefined' &&
        typeof (DeviceMotionEvent as unknown as MotionPermissionRequest).requestPermission === 'function'
    )
}

function wait(ms: number): Promise<void> {
    return new Promise((resolve) => setTimeout(resolve, ms))
}

function answerOf(decision: DecideResponseApi | null): DecisionAnswerApi | null {
    const answer = decision?.answers[ANSWER_QUESTION_ID] as DecisionAnswerApi | undefined
    return answer?.type === 'choice' ? answer : null
}

