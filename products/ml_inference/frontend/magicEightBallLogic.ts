export type magicEightBallLogicType = MakeLogicType<
    magicEightBallLogicValues,
    magicEightBallLogicActions,
    Record<string, any>,
    magicEightBallLogicMeta
>

export const magicEightBallLogic = kea<magicEightBallLogicType>([
    path(['products', 'ml_inference', 'frontend', 'magicEightBallLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        setQuestion: (question: string) => ({ question }),
        setMotionAllowed: (motionAllowed: boolean) => ({ motionAllowed }),
        requestMotionPermission: true,
    }),
    loaders(({ values }) => ({
        decision: [
            null as DecideResponseApi | null,
            {
                ask: async () => {
                    if (values.currentTeamId === null) {
                        throw new Error('No project selected')
                    }
                    // Promise.all rejects on the first error, which cuts the shake short when the request fails fast.
                    const [decision] = await Promise.allSettled([
                        mlInferenceDecisionsDecideCreate(
                            String(values.currentTeamId),
                            buildEightBallRequest(values.question)
                        ),
                        wait(MIN_SHAKE_MS),
                    ])
                    if (decision.status === 'rejected') {
                        throw decision.reason
                    }
                    return decision.value
                },
            },
        ],
    })),
    reducers(() => ({
        question: ['', { setQuestion: (_, { question }) => question }],
        askError: [
            null as string | null,
            {
                ask: () => null,
                askFailure: (_, { error }) => error,
            },
        ],
        motionAllowed: [!motionNeedsPermission(), { setMotionAllowed: (_, { motionAllowed }) => motionAllowed }],
    })),
    selectors({
        answer: [
            (s) => [s.decision],
            (decision: DecideResponseApi | null): string | null => answerOf(decision)?.choice ?? null,
        ],
        confidence: [
            (s) => [s.decision],
            (decision: DecideResponseApi | null): number | null => answerOf(decision)?.confidence ?? null,
        ],
        askDisabledReason: [
            (s) => [s.question, s.decisionLoading],
            (question: string, decisionLoading: boolean): string | null => {
                if (decisionLoading) {
                    return 'The ball is thinking'
                }
                if (!question.trim()) {
                    return 'Ask a product question first'
                }
                return null
            },
        ],
    }),
    listeners(({ actions }) => ({
        requestMotionPermission: async () => {
            try {
                const result = await (DeviceMotionEvent as unknown as MotionPermissionRequest).requestPermission?.()
                actions.setMotionAllowed(result === 'granted')
            } catch {
                actions.setMotionAllowed(false)
            }
        },
    })),
])
