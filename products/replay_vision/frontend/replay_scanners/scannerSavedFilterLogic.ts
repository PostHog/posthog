import { MakeLogicType, connect, kea, key, listeners, path, props } from 'kea'
import type { FieldName } from 'kea-forms'

import { lemonToast } from 'lib/lemon-ui/LemonToast'
import posthog from 'lib/posthog-typed'
import { sessionRecordingSavedFiltersLogic } from 'scenes/session-recordings/filters/sessionRecordingSavedFiltersLogic'

import { RecordingsQuery } from '~/queries/schema/schema-general'
import { SessionRecordingPlaylistType } from '~/types'

import { replayScannerLogic } from './replayScannerLogic'
import { applySavedFilterToScannerQuery } from './scannerQueryFilters'

export interface ScannerSavedFilterLogicProps {
    scannerId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scannerSavedFilterLogicActions {
    setScannerValue: (
        key: FieldName,
        value: any
    ) => {
        name: FieldName
        value: any
    } // replayScannerLogic
    clearPendingFilterApplication: () => {
        value: true
    } // sessionRecordingSavedFiltersLogic
    requestApplySavedFilter: (filter: SessionRecordingPlaylistType) => {
        filter: SessionRecordingPlaylistType
    } // sessionRecordingSavedFiltersLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scannerSavedFilterLogicMeta {
    key: string
}

export type scannerSavedFilterLogicType = MakeLogicType<
    {},
    scannerSavedFilterLogicActions,
    ScannerSavedFilterLogicProps,
    scannerSavedFilterLogicMeta
>

/** Applies a saved filter pick from the scanner's filter search. Only the scanner filter editor mounts it. */
export const scannerSavedFilterLogic = kea<scannerSavedFilterLogicType>([
    path((key) => ['products', 'replay_vision', 'frontend', 'replay_scanners', 'scannerSavedFilterLogic', key]),
    props({} as ScannerSavedFilterLogicProps),
    key((props) => props.scannerId),
    connect((props: ScannerSavedFilterLogicProps) => ({
        actions: [
            sessionRecordingSavedFiltersLogic,
            ['requestApplySavedFilter', 'clearPendingFilterApplication'],
            replayScannerLogic({ id: props.scannerId }),
            ['setScannerValue'],
        ],
    })),
    listeners(({ actions, props }) => ({
        requestApplySavedFilter: ({ filter }) => {
            // Cleared at once, or the replay page applies this pick the next time it mounts.
            actions.clearPendingFilterApplication()
            const scanner = replayScannerLogic({ id: props.scannerId }).values.scanner
            const result = applySavedFilterToScannerQuery((scanner?.query as RecordingsQuery | null) ?? null, filter)
            posthog.capture('replay_vision_scanner_saved_filter_applied', {
                scanner_id: props.scannerId === 'new' ? null : props.scannerId,
                is_new_scanner: props.scannerId === 'new',
                saved_filter_short_id: filter.short_id,
                result: result.status,
            })
            if (result.status === 'experiment-filter') {
                lemonToast.warning(
                    "This saved filter targets an experiment, so it can't be copied to a scanner. Create an experiment scanner from the experiment instead."
                )
                return
            }
            if (result.status === 'no-filters') {
                lemonToast.warning('This saved filter has no filters to copy.')
                return
            }
            actions.setScannerValue('query', result.query)
            lemonToast.success(`Copied the filters from "${filter.name || filter.derived_name || 'Unnamed'}"`)
        },
    })),
])
