import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import type { FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { urls } from 'scenes/urls'

import { Breadcrumb } from '~/types'

export enum ReplayScannerTab {
    Overview = 'overview',
    Observations = 'observations',
    Calibration = 'calibration',
    OnDemand = 'on-demand',
    Backfills = 'backfills',
    Configuration = 'configuration',
    Actions = 'actions',
    Scouts = 'scouts',
}

const SCANNER_TABS: ReplayScannerTab[] = Object.values(ReplayScannerTab)
// The at-a-glance Overview (charts + stat panels) is the landing tab; Observations is the drill-down list.
const DEFAULT_TAB: ReplayScannerTab = ReplayScannerTab.Overview

function parseTab(tab: unknown): ReplayScannerTab {
    return SCANNER_TABS.includes(tab as ReplayScannerTab) ? (tab as ReplayScannerTab) : DEFAULT_TAB
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayScannerSceneLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    activeTab: ReplayScannerTab
    breadcrumbs: Breadcrumb[]
    scannerId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayScannerSceneLogicActions {
    setActiveTab: (tab: ReplayScannerTab) => {
        tab: ReplayScannerTab
    }
    setScannerId: (scannerId: string) => {
        scannerId: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayScannerSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        breadcrumbs: (scannerId: string) => Breadcrumb[]
    }
}

export type replayScannerSceneLogicType = MakeLogicType<
    replayScannerSceneLogicValues,
    replayScannerSceneLogicActions,
    Record<string, any>,
    replayScannerSceneLogicMeta
>

export const replayScannerSceneLogic = kea<replayScannerSceneLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'replayScannerSceneLogic']),

    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),

    actions({
        setScannerId: (scannerId: string) => ({ scannerId }),
        setActiveTab: (tab: ReplayScannerTab) => ({ tab }),
    }),

    reducers({
        scannerId: [
            'new' as string,
            {
                setScannerId: (_, { scannerId }) => scannerId,
            },
        ],
        activeTab: [
            // The explicit cast keeps kea-typegen inferring the whole enum, not just this member.
            DEFAULT_TAB as ReplayScannerTab,
            {
                setActiveTab: (_, { tab }) => tab,
            },
        ],
    }),

    selectors({
        breadcrumbs: [
            (s) => [s.scannerId],
            (scannerId: string): Breadcrumb[] => [
                {
                    key: 'replay-vision',
                    name: 'Replay vision',
                    path: urls.replayVision(),
                    iconType: 'replay_vision',
                },
                {
                    key: scannerId === 'new' ? 'new-scanner' : `scanner-${scannerId}`,
                    name: scannerId === 'new' ? 'New scanner' : 'Scanner',
                    path: urls.replayVision(scannerId),
                },
            ],
        ],
    }),

    actionToUrl(({ values }) => ({
        setActiveTab: () => {
            const searchParams = { ...router.values.searchParams }
            if (values.activeTab === DEFAULT_TAB) {
                delete searchParams.tab
            } else {
                searchParams.tab = values.activeTab
            }
            return [router.values.location.pathname, searchParams, router.values.hashParams, { replace: true }]
        },
    })),

    urlToAction(({ actions, values }) => ({
        [urls.replayVision(':id')]: ({ id }, searchParams) => {
            const scannerId = id || 'new'
            if (scannerId !== values.scannerId) {
                actions.setScannerId(scannerId)
            }
            let tab = parseTab(searchParams.tab)
            // Scouts is feature-flagged and its tab isn't rendered without the flag, so a
            // `?tab=scouts` URL (a shared link, a stale bookmark) would otherwise select a tab with
            // no content and show a blank pane. Fall back to the default tab when the flag is off.
            if (tab === ReplayScannerTab.Scouts && !values.featureFlags[FEATURE_FLAGS.REPLAY_VISION_SCOUT_DIGESTS]) {
                tab = DEFAULT_TAB
            }
            if (tab !== values.activeTab) {
                actions.setActiveTab(tab)
            }
        },
    })),
])
