const DEFAULT_DATE_FROM = '-14d'

// Calmer than the 3s in-flight default: first scheduled results take minutes, not seconds.
const FIRST_SCAN_POLL_INTERVAL_MS = 15_000

// The pending panel hides the overview's reload affordances, so after this many straight failed
// checks it has to admit the failure itself instead of spinning on a promise it can't verify.
const FIRST_SCAN_CHECK_FAILING_AFTER = 3

export interface CreditLimitStats {
    limit: number
    used: number
    usedPct: number
    limitReached: boolean
}

/** The bucket size of the Overview charts; the drill-down only knows how to map day buckets onto the Observations tab. */
export const OVERVIEW_CHART_INTERVAL: IntervalType = 'day'

/** Observations-tab search params for a clicked Overview chart point, or null when the bucket can't map to a day filter. */
export function observationsDrilldownSearchParams(options: {
    day: string | number | undefined
    breakdown?: unknown
    interval: IntervalType
    scannerType?: ScannerType
}): ({ tab: 'observations' } & ObservationsUrlParams) | null {
    const { day, breakdown, interval, scannerType } = options
    if (interval !== 'day' || typeof day !== 'string' || !/^\d{4}-\d{2}-\d{2}/.test(day)) {
        return null
    }
    const date = day.slice(0, 10)
    const params: { tab: 'observations' } & ObservationsUrlParams = {
        tab: 'observations',
        date_from: date,
        date_to: date,
    }
    // The monitor chart plots the yes rate, so land on the sessions behind the numerator.
    if (scannerType === 'monitor') {
        params.verdict = 'yes'
    }
    const tag = Array.isArray(breakdown) ? breakdown[0] : breakdown
    // The "Other"/"None" breakdown buckets aren't real tags, so they can't narrow the tab.
    if (typeof tag === 'string' && tag && !isOtherBreakdown(tag) && !isNullBreakdown(tag)) {
        params.tags = tag
    }
    return params
}

