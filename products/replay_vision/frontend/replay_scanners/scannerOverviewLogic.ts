// The impact endpoint caps its lookback at 90 days; the overview date range can go wider.
const MAX_IMPACT_WINDOW_DAYS = 90

/**
 * Backs the scanner's Overview tab: the built-in charts and stat panels, with their OWN filter set
 * (date range + verdict/tag), independent of the Observations tab's list filters. It loads the same
 * observations-stats endpoint as the Observations tab, but with these filters — so filtering the
 * overview never disturbs the observations list and vice versa. Impact lives here too, loaded with a
 * window derived from the overview date range so every widget honors the same timing.
 */
export const scannerOverviewLogic = kea<scannerOverviewLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'scannerOverviewLogic']),
    props({} as ScannerOverviewLogicProps),
    key((props) => props.scannerId),

    connect((props: ScannerOverviewLogicProps) => ({
        values: [replayScannerLogic({ id: props.scannerId }), ['scanner']],
        // Bound at build time, so dispatching into the scanner logic can't depend on it being mounted.
        actions: [replayScannerLogic({ id: props.scannerId }), ['loadScannerSuccess', 'scannerWatermarkRefreshed']],
    })),

    actions({
        loadOverviewStats: true,
        loadOverviewStatsSuccess: (stats: ObservationStatsApi) => ({ stats }),
        loadOverviewStatsFailure: true,
        markFirstScanSettled: true,
        setOverviewDateRange: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setOverviewVerdictFilter: (values: ObservationVerdictValue[]) => ({ values }),
        setOverviewTagFilter: (values: string[]) => ({ values }),
        clearOverviewFilters: true,
        drillIntoObservations: (day: string | number | undefined, breakdown?: unknown) => ({ day, breakdown }),
    }),

    reducers({
        overviewDateFrom: [
            DEFAULT_DATE_FROM as string | null,
            {
                setOverviewDateRange: (_, { dateFrom }) => dateFrom,
                clearOverviewFilters: () => DEFAULT_DATE_FROM,
            },
        ],
        overviewDateTo: [
            null as string | null,
            {
                setOverviewDateRange: (_, { dateTo }) => dateTo,
                clearOverviewFilters: () => null,
            },
        ],
        overviewVerdictFilter: [
            [] as ObservationVerdictValue[],
            {
                setOverviewVerdictFilter: (_, { values }) => values,
                clearOverviewFilters: () => [],
            },
        ],
        overviewTagFilter: [
            [] as string[],
            {
                setOverviewTagFilter: (_, { values }) => values,
                clearOverviewFilters: () => [],
            },
        ],
        overviewStatsApi: [
            null as ObservationStatsApi | null,
            {
                loadOverviewStatsSuccess: (_, { stats }) => stats,
            },
        ],
        overviewStatsApiLoading: [
            false,
            {
                loadOverviewStats: () => true,
                loadOverviewStatsSuccess: () => false,
                loadOverviewStatsFailure: () => false,
            },
        ],
        // The clock input for the stuck-scan age cap. Ticked on failures too, so the cap still fires
        // when the endpoint errors forever and no other selector input ever changes.
        overviewStatsCheckedAt: [
            Date.now(),
            {
                loadOverviewStatsSuccess: () => Date.now(),
                loadOverviewStatsFailure: () => Date.now(),
            },
        ],
        overviewStatsFailureCount: [
            0,
            {
                loadOverviewStatsSuccess: () => 0,
                loadOverviewStatsFailure: (state) => state + 1,
            },
        ],
        // Latches the first-scan panel closed for the rest of the mount, so later in-flight
        // observations can't swap the charts back out for the spinner.
        firstScanSettled: [
            false,
            {
                markFirstScanSettled: () => true,
            },
        ],
    }),

    selectors({
        // The date default alone isn't an "active" filter; only the pills (and a non-default date) are.
        hasActiveOverviewFilters: [
            (s) => [s.overviewVerdictFilter, s.overviewTagFilter, s.overviewDateFrom, s.overviewDateTo],
            (
                verdictFilter: ObservationVerdictValue[],
                tagFilter: string[],
                dateFrom: string | null,
                dateTo: string | null
            ): boolean =>
                verdictFilter.length > 0 || tagFilter.length > 0 || dateFrom !== DEFAULT_DATE_FROM || dateTo !== null,
        ],
        // Wrap the shared derivations in inline arrows with explicit return types so kea-typegen
        // can infer them (it can't resolve return types from bare imported-function references).
        availableTags: [
            (s) => [s.overviewStatsApi],
            (stats: ObservationStatsApi | null): string[] => availableTagsFromStats(stats),
        ],
        monitorStats: [
            (s) => [s.overviewStatsApi],
            (stats: ObservationStatsApi | null): MonitorStats => deriveMonitorStats(stats),
        ],
        classifierTagStats: [
            (s) => [s.overviewStatsApi],
            (stats: ObservationStatsApi | null): ClassifierTagStats => deriveClassifierTagStats(stats),
        ],
        scorerSummary: [
            (s) => [s.overviewStatsApi],
            (stats: ObservationStatsApi | null): ScorerSummary | null => deriveScorerSummary(stats),
        ],
        scorerHistogram: [
            (s) => [s.overviewStatsApi],
            (stats: ObservationStatsApi | null): ScorerHistogram | null => deriveScorerHistogram(stats),
        ],
        summarizerFacetStats: [
            (s) => [s.overviewStatsApi],
            (stats: ObservationStatsApi | null): SummarizerFacetStats => deriveSummarizerFacetStats(stats),
        ],
        coverageStats: [
            (s) => [s.overviewStatsApi],
            (stats: ObservationStatsApi | null): CoverageStats => deriveCoverageStats(stats),
        ],
        // While true the Overview swaps its filters + charts for a single "first scan in progress" panel,
        // so a brand-new scanner never shows the generic "no matching events" empty state. Active filters
        // mean the user is slicing data, so the normal panels render then. `overviewStatsCheckedAt`
        // stands in for the current time: reading the clock inside the selector would freeze the age
        // cap whenever the inputs stop changing (e.g. every poll request failing).
        firstScanPending: [
            (s) => [
                s.overviewStatsApi,
                s.scanner,
                s.hasActiveOverviewFilters,
                s.firstScanSettled,
                s.overviewStatsCheckedAt,
            ],
            (
                stats: ObservationStatsApi | null,
                scanner: ReplayScanner | null,
                hasFilters: boolean,
                settled: boolean,
                checkedAt: number
            ): boolean => !settled && !hasFilters && isAwaitingFirstResults(stats, scanner, dayjs(checkedAt)),
        ],
        // The pending panel hides the overview's reload buttons, so it has to surface a failing
        // background check itself instead of spinning forever.
        firstScanCheckFailing: [
            (s) => [s.firstScanPending, s.overviewStatsFailureCount],
            (pending: boolean, failureCount: number): boolean =>
                pending && failureCount >= FIRST_SCAN_CHECK_FAILING_AFTER,
        ],
        // Null when the scanner has no limit set, so callers can render nothing rather than a "0% of 0" panel.
        creditLimitStats: [
            (s) => [s.scanner],
            (scanner: ReplayScanner): CreditLimitStats | null => {
                const limit = scanner.credit_limit
                if (limit == null) {
                    return null
                }
                const used = scanner.credits_used_against_limit
                return {
                    limit,
                    used,
                    usedPct: limit > 0 ? Math.min(100, Math.round((used / limit) * 100)) : 0,
                    // Comes from the API, not from usedPct: a scanner stops as soon as what's left can't
                    // cover another scan, so this can be true below 100%.
                    limitReached: !!scanner.limit_reached,
                }
            },
        ],
    }),

    loaders(({ props, values }) => ({
        overviewImpact: [
            null as ScannerImpactApi | null,
            {
                loadOverviewImpact: async () => {
                    const teamId = teamLogic.values.currentTeamId
                    // Impact only exists for monitors (a qualifier-free predicate); other types show no panel.
                    if (!teamId || props.scannerId === 'new' || values.scanner?.scanner_type !== 'monitor') {
                        return null
                    }
                    const windowDays = Math.min(
                        MAX_IMPACT_WINDOW_DAYS,
                        Math.max(1, daysFromDateRange(values.overviewDateFrom, values.overviewDateTo))
                    )
                    return await visionScannersImpactRetrieve(String(teamId), props.scannerId, {
                        window_days: windowDays,
                    })
                },
            },
        ],
    })),

    listeners(({ actions, cache, props, values }) => {
        const reloadStats = (): void => actions.loadOverviewStats()
        // Only the date range changes the impact window; verdict/tag filters don't apply to impact.
        const reloadDateScoped = (): void => {
            actions.loadOverviewStats()
            actions.loadOverviewImpact()
        }
        // Pending also hangs off the scanner's sweep watermark, which only the scanner endpoint
        // reports; without refreshing it a first sweep that matches nothing would never clear
        // pending. Fetched directly because loadScanner flips scannerLoading, which blanks the scene,
        // and dispatched through the dedicated watermark action so a background refetch can't reset
        // the scanner form or refire the observation loads.
        const refreshScannerWatermark = async (): Promise<void> => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId || props.scannerId === 'new') {
                return
            }
            try {
                const response = await visionScannersRetrieve(String(teamId), props.scannerId)
                actions.scannerWatermarkRefreshed(scannerFromApi(response))
            } catch {
                // A failed background refresh just waits for the next poll tick.
            }
        }
        // Each tick refreshes stats and the sweep watermark in the background, so the pending panel
        // dissolves into the real Overview on its own. Failing ticks keep polling without toasting
        // (see the loadOverviewStats catch); the panel surfaces them via firstScanCheckFailing.
        const firstScanPollTick = (): void => {
            if (!values.firstScanPending) {
                cache.firstScanPollArmed = false
                return
            }
            // Re-arm at tick time rather than response time, so the gap stays one interval per tick
            // however the stats and watermark responses interleave.
            scheduleObservationPoll(cache.disposables, true, firstScanPollTick, FIRST_SCAN_POLL_INTERVAL_MS)
            actions.loadOverviewStats()
            void refreshScannerWatermark()
        }
        // The single owner of the poll timer and the pending latch, run after every action that can
        // move firstScanPending: arms once per pending spell (the tick re-arms itself), stops the
        // timer the moment pending clears, and latches the first true to false flip for this mount.
        // Filters also flip pending false, so only a flip with no filters active means results arrived;
        // latching on a filtered flip would keep the panel from returning once the filter is cleared.
        const syncFirstScanPoll = (): void => {
            const pending = values.firstScanPending
            if (cache.firstScanWasPending && !pending && !values.hasActiveOverviewFilters && !values.firstScanSettled) {
                actions.markFirstScanSettled()
            }
            cache.firstScanWasPending = cache.firstScanWasPending || pending
            if (!pending) {
                cache.firstScanPollArmed = false
                scheduleObservationPoll(cache.disposables, false, firstScanPollTick, FIRST_SCAN_POLL_INTERVAL_MS)
            } else if (!cache.firstScanPollArmed) {
                cache.firstScanPollArmed = true
                scheduleObservationPoll(cache.disposables, true, firstScanPollTick, FIRST_SCAN_POLL_INTERVAL_MS)
            }
        }
        return {
            setOverviewDateRange: () => {
                reloadDateScoped()
                syncFirstScanPoll()
            },
            setOverviewVerdictFilter: () => {
                reloadStats()
                syncFirstScanPoll()
            },
            setOverviewTagFilter: () => {
                reloadStats()
                syncFirstScanPoll()
            },
            clearOverviewFilters: () => {
                reloadDateScoped()
                syncFirstScanPoll()
            },
            loadOverviewStatsSuccess: syncFirstScanPoll,
            loadOverviewStatsFailure: syncFirstScanPoll,
            scannerWatermarkRefreshed: syncFirstScanPoll,
            // Impact needs the scanner type; refire once the scanner (and its type) resolves. The
            // poll syncs too: pending depends on the sweep watermark, which may resolve after the
            // first stats response.
            loadScannerSuccess: () => {
                actions.loadOverviewImpact()
                syncFirstScanPoll()
            },

            drillIntoObservations: ({ day, breakdown }) => {
                const searchParams = observationsDrilldownSearchParams({
                    day,
                    breakdown,
                    interval: OVERVIEW_CHART_INTERVAL,
                    scannerType: values.scanner?.scanner_type,
                })
                if (searchParams) {
                    // Replaces any existing observation filters: the drill-down defines the slice being inspected.
                    router.actions.push(urls.replayVision(props.scannerId), searchParams)
                }
            },

            loadOverviewStats: async (_, breakpoint) => {
                const teamId = teamLogic.values.currentTeamId
                if (!teamId || props.scannerId === 'new') {
                    actions.loadOverviewStatsFailure()
                    return
                }
                try {
                    const params: Record<string, string | number> = {
                        recent_days: daysFromDateRange(values.overviewDateFrom, values.overviewDateTo),
                    }
                    if (values.overviewVerdictFilter.length > 0) {
                        params.verdict = values.overviewVerdictFilter.join(',')
                    }
                    if (values.overviewTagFilter.length > 0) {
                        params.tags = values.overviewTagFilter.join(',')
                    }
                    if (values.overviewDateFrom) {
                        params.date_from = values.overviewDateFrom
                    }
                    if (values.overviewDateTo) {
                        params.date_to = values.overviewDateTo
                    }
                    const response = await visionScannersObservationsStatsRetrieve(
                        String(teamId),
                        props.scannerId,
                        params
                    )
                    breakpoint()
                    actions.loadOverviewStatsSuccess(response)
                } catch (error) {
                    if (error instanceof Error && isBreakpoint(error)) {
                        throw error
                    }
                    // Background retries behind the pending panel would otherwise stack a toast per interval.
                    if (!values.firstScanPending) {
                        lemonToast.error('Failed to load overview stats')
                    }
                    actions.loadOverviewStatsFailure()
                }
            },
        }
    }),

    afterMount(({ actions }) => {
        actions.loadOverviewStats()
        // If the scanner is already cached, loadScannerSuccess won't refire — load impact now too.
        actions.loadOverviewImpact()
    }),
])
