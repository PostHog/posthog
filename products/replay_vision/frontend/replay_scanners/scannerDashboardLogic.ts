import { MakeLogicType, actions, connect, kea, key, listeners, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { type FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { visionScannersCreateDashboardCreate } from '../generated/api'
import { replayScannerLogic } from './replayScannerLogic'
import type { ScannerFormValues } from './types'

export interface ScannerDashboardLogicProps {
    scannerId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scannerDashboardLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    scanner: ScannerFormValues // replayScannerLogic
    createdDashboardId: number | null
    createdDashboardIdLoading: boolean
    dashboardId: number | null
    showDashboardOffer: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scannerDashboardLogicActions {
    createDashboard: () => any
    createDashboardFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    createDashboardSuccess: (
        createdDashboardId: number | null,
        payload?: any
    ) => {
        createdDashboardId: number | null
        payload?: any
    }
    dashboardOfferShown: () => {
        value: true
    }
    dismissDashboardOffer: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scannerDashboardLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        dashboardId: (createdDashboardId: number | null, scanner: ScannerFormValues) => number | null
        showDashboardOffer: (
            featureFlags: Record<string, boolean | string>,
            scanner: ScannerFormValues,
            dashboardId: number | null
        ) => boolean
    }
}

export type scannerDashboardLogicType = MakeLogicType<
    scannerDashboardLogicValues,
    scannerDashboardLogicActions,
    ScannerDashboardLogicProps,
    scannerDashboardLogicMeta
>

// The dismissal is per viewer and per scanner, so it lives in the banner's localStorage key rather than on the scanner.
// pinned: localStorage key prefix, renaming it shows the offer again to everyone who dismissed it
export const scannerDashboardOfferDismissKey = (scannerId: string): string =>
    `replay-vision-scanner-dashboard-offer-${scannerId}`

export const scannerDashboardLogic = kea<scannerDashboardLogicType>([
    props({} as ScannerDashboardLogicProps),
    key((props) => props.scannerId),
    path((key) => ['products', 'replay_vision', 'frontend', 'replay_scanners', 'scannerDashboardLogic', key]),
    connect((props: ScannerDashboardLogicProps) => ({
        values: [replayScannerLogic({ id: props.scannerId }), ['scanner'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        dashboardOfferShown: true,
        dismissDashboardOffer: true,
    }),
    loaders(({ props, values }) => ({
        createdDashboardId: [
            null as number | null,
            {
                createDashboard: async (): Promise<number | null> => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        return values.createdDashboardId
                    }
                    try {
                        const response = await visionScannersCreateDashboardCreate(String(teamId), props.scannerId)
                        lemonToast.success(`Dashboard "${response.name}" created`, {
                            button: {
                                label: 'Open dashboard',
                                action: () => router.actions.push(urls.dashboard(response.dashboard_id)),
                            },
                        })
                        return response.dashboard_id
                    } catch (error: any) {
                        lemonToast.error(`Couldn't create the dashboard${error?.detail ? `: ${error.detail}` : ''}`)
                        return values.createdDashboardId
                    }
                },
            },
        ],
    })),
    selectors({
        // The scanner response is not refetched after creation, so a dashboard created here wins over the stale field.
        dashboardId: [
            (s) => [s.createdDashboardId, s.scanner],
            (createdDashboardId: number | null, scanner: ScannerFormValues): number | null =>
                createdDashboardId ?? scanner?.dashboard_id ?? null,
        ],
        showDashboardOffer: [
            (s) => [s.featureFlags, s.scanner, s.dashboardId],
            (
                featureFlags: Record<string, boolean | string>,
                scanner: ScannerFormValues,
                dashboardId: number | null
            ): boolean =>
                !!featureFlags[FEATURE_FLAGS.REPLAY_VISION_SCANNER_DASHBOARD] &&
                !!scanner?.dashboard_suggested &&
                dashboardId === null,
        ],
    }),
    listeners(({ props, values }) => ({
        dashboardOfferShown: () => {
            // pinned: analytics event name, renaming breaks the offer funnel
            posthog.capture('replay_vision_scanner_dashboard_offer_shown', {
                scanner_id: props.scannerId,
                scanner_type: values.scanner?.scanner_type,
            })
        },
        dismissDashboardOffer: () => {
            // pinned: analytics event name, renaming breaks the offer funnel
            posthog.capture('replay_vision_scanner_dashboard_offer_dismissed', {
                scanner_id: props.scannerId,
                scanner_type: values.scanner?.scanner_type,
            })
        },
    })),
])
