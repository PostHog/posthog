import { MakeLogicType, connect, kea, key, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { visionScannersObservationsList } from '../generated/api'
import type { ReplayObservationApi } from '../generated/api.schemas'

export interface HighlightFeedGroupLogicProps {
    /** The card's observation. The backend resolves its feed group from it. */
    observationId: string
    scannerId: string
    dateFrom: string
    /** The feed's kinds as its `categories` value, unset when all are on. */
    categories?: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface highlightFeedGroupLogicValues {
    currentTeamId: number | null // teamLogic
    members: WatchGroupMembers | null
    membersLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface highlightFeedGroupLogicActions {
    loadMembers: (_: void) => void
    loadMembersFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadMembersSuccess: (
        members: WatchGroupMembers | null,
        payload?: any
    ) => {
        members: WatchGroupMembers | null
        payload?: any
    }
}

export interface WatchGroupMembers {
    /** The first few of the group's other sessions. */
    shown: ReplayObservationApi[]
    /** How many other sessions the list endpoint matched, which can exceed what the card counted. */
    total: number
}

export type highlightFeedGroupLogicType = MakeLogicType<
    highlightFeedGroupLogicValues,
    highlightFeedGroupLogicActions,
    HighlightFeedGroupLogicProps
>

/** How many of the group's other sessions the card lists before it links to the full list. */
export const WATCH_GROUP_PREVIEW_SIZE = 5

/** The other sessions in a feed card's feed group, loaded the first time the card's popover opens. */
export const highlightFeedGroupLogic = kea<highlightFeedGroupLogicType>([
    path((key) => ['products', 'replay_vision', 'frontend', 'replay_scanners', 'highlightFeedGroupLogic', key]),
    props({} as HighlightFeedGroupLogicProps),
    // The window and kinds are part of the key, so a change lists the matching sessions rather than the cached ones.
    key((props) => `${props.observationId}:${props.dateFrom}:${props.categories ?? ''}`),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    loaders(({ props, values }) => ({
        members: [
            null as WatchGroupMembers | null,
            {
                loadMembers: async (): Promise<WatchGroupMembers | null> => {
                    if (!values.currentTeamId) {
                        return null
                    }
                    const page = await visionScannersObservationsList(String(values.currentTeamId), props.scannerId, {
                        watch_group: props.observationId,
                        date_from: props.dateFrom,
                        watch_category: props.categories,
                        limit: WATCH_GROUP_PREVIEW_SIZE + 1,
                    })
                    // The card's own session already sits above the list.
                    const others = page.results.filter((member) => member.id !== props.observationId)
                    return {
                        shown: others.slice(0, WATCH_GROUP_PREVIEW_SIZE),
                        total: page.count - (page.results.length - others.length),
                    }
                },
            },
        ],
    })),
])
