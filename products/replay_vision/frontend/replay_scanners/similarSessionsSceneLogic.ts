/** The feed group a Highlights card opened, with the feed's date window and kinds so the list matches the card's count. */
export interface SimilarSessionsQuery {
    /** The card's observation. The backend resolves its feed group from it. */
    observationId: string
    /** Feed groups are per scanner, and the list endpoint is scoped to one. */
    scannerId: string | null
    dateFrom: string | null
    /** The feed's kinds as its `categories` value, null when all are on. */
    categories: string | null
}

export interface SimilarSessionsPage {
    /** Every session loaded so far, the card's own session included. */
    results: ReplayObservationApi[]
    count: number
}

export const SIMILAR_SESSIONS_PAGE_SIZE = 20

/** The page that lists every session in a feed card's group, so a reader can scan them side by side. */
export function similarSessionsUrl({ observationId, scannerId, dateFrom, categories }: SimilarSessionsQuery): string {
    return combineUrl(urls.replayVisionSimilarSessions(observationId), {
        ...(scannerId ? { scanner: scannerId } : {}),
        ...(dateFrom ? { date_from: dateFrom } : {}),
        ...(categories ? { watch_category: categories } : {}),
    }).url
}

