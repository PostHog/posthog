export const similarSessionsSceneLogic = kea<similarSessionsSceneLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'similarSessionsSceneLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        setQuery: (query: SimilarSessionsQuery) => ({ query }),
    }),
    loaders(({ values }) => {
        const loadPage = async (offset: number): Promise<SimilarSessionsPage | null> => {
            const { query, currentTeamId } = values
            if (!currentTeamId || !query?.scannerId) {
                return null
            }
            const page = await visionScannersObservationsList(String(currentTeamId), query.scannerId, {
                watch_group: query.observationId,
                date_from: query.dateFrom ?? undefined,
                watch_category: query.categories ?? undefined,
                limit: SIMILAR_SESSIONS_PAGE_SIZE,
                offset,
            })
            return { results: page.results, count: page.count }
        }
        return {
            sessions: [
                null as SimilarSessionsPage | null,
                {
                    loadSessions: async (_, breakpoint) => {
                        const page = await loadPage(0)
                        breakpoint()
                        return page
                    },
                    loadMoreSessions: async (_, breakpoint) => {
                        const loaded = values.sessions
                        const page = await loadPage(loaded?.results.length ?? 0)
                        breakpoint()
                        if (!loaded || !page) {
                            return page
                        }
                        // A session that moved between pages while the reader scrolled must not show twice.
                        const seen = new Set(loaded.results.map((session) => session.id))
                        return {
                            results: [...loaded.results, ...page.results.filter((session) => !seen.has(session.id))],
                            count: page.count,
                        }
                    },
                },
            ],
        }
    }),
    reducers({
        query: [
            null as SimilarSessionsQuery | null,
            {
                setQuery: (_, { query }) => query,
            },
        ],
        sessions: {
            // A different group must not show the last group's sessions while it loads.
            setQuery: () => null,
        },
        sessionsFailed: [
            false,
            {
                setQuery: () => false,
                loadSessions: () => false,
                loadSessionsSuccess: () => false,
                loadSessionsFailure: () => true,
            },
        ],
        moreFailed: [
            false,
            {
                setQuery: () => false,
                loadMoreSessions: () => false,
                loadMoreSessionsSuccess: () => false,
                loadMoreSessionsFailure: () => true,
            },
        ],
    }),
    selectors({
        breadcrumbs: [
            (s) => [s.query],
            (query: SimilarSessionsQuery | null): Breadcrumb[] => [
                VISION_ROOT_BREADCRUMB,
                highlightFeedBreadcrumb(),
                {
                    key: 'similar-sessions',
                    name: 'Similar sessions',
                    path: query ? similarSessionsUrl(query) : urls.replayVision(),
                },
            ],
        ],
    }),
    listeners(({ actions }) => ({
        setQuery: () => actions.loadSessions(),
    })),
    urlToAction(({ actions, values }) => ({
        [urls.replayVisionSimilarSessions(':observationId')]: ({ observationId }, searchParams) => {
            const read = (key: string): string | null =>
                typeof searchParams[key] === 'string' && searchParams[key] ? searchParams[key] : null
            const query: SimilarSessionsQuery = {
                observationId: observationId ?? '',
                scannerId: read('scanner'),
                dateFrom: read('date_from'),
                categories: read('watch_category'),
            }
            if (!objectsEqual(query, values.query)) {
                actions.setQuery(query)
            }
        },
    })),
])
