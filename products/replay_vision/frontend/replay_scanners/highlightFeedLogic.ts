export const DEFAULT_FEED_DATE_FROM: string = '-7d'
/** The windows the feed offers, shortest first. */
export const FEED_DATE_OPTIONS: { value: string; label: string }[] = [
    { value: '-24h', label: 'Last 24 hours' },
    { value: '-7d', label: 'Last 7 days' },
    { value: '-30d', label: 'Last 30 days' },
    { value: '-90d', label: 'Last 90 days' },
]
export const FEED_CATEGORIES: HighlightFeedCategoryEnumApi[] = Object.values(HighlightFeedCategoryEnumApi)

export function feedWindowOption(dateFrom: string): { value: string; label: string } | undefined {
    return FEED_DATE_OPTIONS.find((option) => option.value === dateFrom)
}

/** The next longer window the feed offers, or undefined at the longest. */
export function longerFeedWindow(dateFrom: string): { value: string; label: string } | undefined {
    const index = FEED_DATE_OPTIONS.findIndex((option) => option.value === dateFrom)
    return index >= 0 ? FEED_DATE_OPTIONS[index + 1] : undefined
}

/** "in the last 7 days" for an offered window, for copy that names the window the reader picked. */
export function feedWindowPhrase(dateFrom: string): string {
    const option = feedWindowOption(dateFrom)
    return option ? `in the ${option.label.toLowerCase()}` : 'in this window'
}

export const FEED_PAGE_SIZE = 20

/** The `categories` query value, left out when every kind is on so all-on shares the default cache. */
export function feedCategoriesParam(categories: HighlightFeedCategoryEnumApi[]): string | undefined {
    return categories.length < FEED_CATEGORIES.length ? categories.join(',') : undefined
}

function feedParams(values: highlightFeedLogicValues): VisionScannersHighlightFeedRetrieveParams {
    const params: VisionScannersHighlightFeedRetrieveParams = { date_from: values.dateFrom, limit: FEED_PAGE_SIZE }
    if (values.scopedToMine && values.user) {
        params.created_by = String(values.user.id)
    }
    const categories = feedCategoriesParam(values.categories)
    if (categories) {
        params.categories = categories
    }
    return params
}

function reportFiltered(values: highlightFeedLogicValues): void {
    posthog.capture('replay_vision_highlight_feed_filtered', {
        date_from: values.dateFrom,
        only_my_scanners: values.scopedToMine,
        categories: values.categories,
    })
}

/** Data for the Highlights tab: the window's most watchable observations, ranked server-side. */
export const highlightFeedLogic = kea<highlightFeedLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'highlightFeedLogic']),

    connect(() => ({
        values: [
            userLogic,
            ['user'],
            // An empty feed cannot be explained from the feed alone: the reason lives in the fleet's
            // state and the org's budget.
            visionScannersListLogic,
            ['scanners', 'scannersLoading'],
            visionQuotaLogic,
            ['quota', 'quotaLoading'],
        ],
    })),

    actions({
        setDateFrom: (dateFrom: string) => ({ dateFrom }),
        setCategories: (categories: HighlightFeedCategoryEnumApi[]) => ({ categories }),
        setOnlyMyScanners: (onlyMyScanners: boolean) => ({ onlyMyScanners }),
        loadFeed: true,
        setFeedLoad: (load: HighlightFeedLoad) => ({ load }),
        extendFeedLoad: (load: HighlightFeedLoad) => ({ load }),
        setFeedPaging: (hasMore: boolean, asOf: string | null, served: number) => ({ hasMore, asOf, served }),
        cardSeen: (item: HighlightFeedItemApi, position: number) => ({ item, position }),
        dismissItem: (item: HighlightFeedItemApi, position: number, reason: FeedDismissalReasonEnumApi | null) => ({
            item,
            position,
            reason,
        }),
        restoreItem: (item: HighlightFeedItemApi, position: number) => ({ item, position }),
    }),

    loaders(({ values, actions, cache }) => ({
        feedItems: [
            null as HighlightFeedItemApi[] | null,
            {
                loadFeed: async (_, breakpoint) => {
                    // Counts loads from the moment one starts, so a page requested for an older load is dropped.
                    cache.feedGeneration = (cache.feedGeneration ?? 0) + 1
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        // Reporting this as a successful empty result would read as "nothing to watch";
                        // fail instead so the tab shows the error state and a retry.
                        throw new Error('No current team')
                    }
                    const response = await visionScannersHighlightFeedRetrieve(String(teamId), feedParams(values))
                    // Drop out-of-order responses — the most recent filter change owns the feed.
                    breakpoint()
                    actions.setFeedLoad(newHighlightFeedLoad(response.results))
                    actions.setFeedPaging(response.has_more ?? false, response.as_of ?? null, response.results.length)
                    return response.results
                },
                loadMoreFeed: async (_, breakpoint) => {
                    const teamId = teamLogic.values.currentTeamId
                    const load = values.feedLoad
                    if (!teamId || !load || !values.feedHasMore || !values.feedAsOf) {
                        return values.feedItems
                    }
                    // Counted against what the server returned, so neither a hidden card nor a deduplicated one shifts the next page.
                    const offset = values.feedServed
                    const generation = cache.feedGeneration
                    let response
                    try {
                        response = await visionScannersHighlightFeedRetrieve(String(teamId), {
                            ...feedParams(values),
                            offset,
                            as_of: values.feedAsOf,
                        })
                    } catch (error) {
                        // A failure for a load the reader has since replaced must not stop paging the new one.
                        if (cache.feedGeneration !== generation) {
                            return values.feedItems
                        }
                        throw error
                    }
                    // A newer request for the next page supersedes this one, so the same page never appends twice.
                    breakpoint()
                    // A filter change while this page was in flight started a new load, which owns the feed now.
                    if (cache.feedGeneration !== generation || values.feedLoad?.feedLoadId !== load.feedLoadId) {
                        return values.feedItems
                    }
                    const page = response.results.filter((item) => !(item.observation.id in load.positions))
                    actions.extendFeedLoad(withNextPage(load, page))
                    // An empty page cannot advance the offset, so it ends paging rather than repeating the request.
                    actions.setFeedPaging(
                        (response.has_more ?? false) && response.results.length > 0,
                        response.as_of ?? null,
                        offset + response.results.length
                    )
                    posthog.capture('replay_vision_highlight_feed_page_loaded', {
                        ...servedListProperties(values.feedLoad, page),
                        offset,
                        clip_count: page.length,
                        has_more: response.has_more,
                    })
                    return [...(values.feedItems ?? []), ...page]
                },
            },
        ],
    })),

    reducers({
        feedItems: {
            dismissItem: (state, { item }) => withoutFeedItem(state, item.observation.id),
            restoreItem: (state, { item, position }) => withFeedItemRestored(state, item, position),
        },
        feedLoad: [
            null as HighlightFeedLoad | null,
            {
                setFeedLoad: (_, { load }) => load,
                extendFeedLoad: (_, { load }) => load,
            },
        ],
        feedHasMore: [
            false,
            {
                loadFeed: () => false,
                setFeedPaging: (_, { hasMore }) => hasMore,
            },
        ],
        feedAsOf: [
            null as string | null,
            {
                loadFeed: () => null,
                setFeedPaging: (_, { asOf }) => asOf,
            },
        ],
        feedServed: [
            0,
            {
                loadFeed: () => 0,
                setFeedPaging: (_, { served }) => served,
            },
        ],
        feedMoreFailed: [
            false,
            {
                loadFeed: () => false,
                loadMoreFeed: () => false,
                loadMoreFeedFailure: () => true,
            },
        ],
        dateFrom: [
            DEFAULT_FEED_DATE_FROM,
            {
                setDateFrom: (_, { dateFrom }) => dateFrom,
            },
        ],
        // Keyed by team, so the choice made on one team does not carry into another team's feed.
        onlyMyScanners: [
            false,
            { persist: true, prefix: `${getCurrentTeamIdOrNone() ?? 'unknown'}__` },
            {
                setOnlyMyScanners: (_, { onlyMyScanners }) => onlyMyScanners,
            },
        ],
        // Keyed by team like the scope, since each project sells something different. Stores what is hidden, so a
        // kind added later shows up for everyone.
        hiddenCategories: [
            [] as string[],
            { persist: true, prefix: `${getCurrentTeamIdOrNone() ?? 'unknown'}__` },
            {
                setCategories: (_, { categories }) =>
                    FEED_CATEGORIES.filter((category) => !categories.includes(category)),
            },
        ],
        feedFailed: [
            false,
            {
                loadFeed: () => false,
                loadFeedFailure: () => true,
            },
        ],
        // A filter change reloads page one, unlike loading the next page, which shares the loader.
        feedReloading: [
            false,
            {
                loadFeed: () => true,
                loadFeedSuccess: () => false,
                loadFeedFailure: () => false,
            },
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        setFeedLoad: ({ load }) => {
            cache.impressions.start(load)
        },
        extendFeedLoad: ({ load }) => {
            cache.impressions.extend(load)
        },
        cardSeen: ({ item, position }) => {
            cache.impressions.add(item, position)
        },
        dismissItem: async ({ item, position, reason }) => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                return
            }
            const loadId = values.feedLoad?.feedLoadId
            await dismissFeedItem({
                teamId,
                item,
                reason,
                properties: cardProperties(values.feedLoad, item, position, 'feed_tab'),
                restore: () => values.feedLoad?.feedLoadId === loadId && actions.restoreItem(item, position),
            })
        },
        setDateFrom: () => {
            reportFiltered(values)
            actions.loadFeed()
        },
        // The menu stays open while boxes are ticked, so a burst of clicks waits for one request.
        setCategories: async (_, breakpoint) => {
            await breakpoint(300)
            reportFiltered(values)
            actions.loadFeed()
        },
        // The `scopedToMine` subscription reloads, so a tab switch sends one request.
        setOnlyMyScanners: () => {
            reportFiltered(values)
        },
        loadFeedSuccess: ({ feedItems }) => {
            const items = feedItems ?? []
            // The click event reports the reason a reader picked; without this one nothing reports the mix
            // they were offered, so a ranking change cannot be read after it ships.
            const countByReasonKind: Record<string, number> = {}
            for (const item of items) {
                countByReasonKind[item.reason.kind] = (countByReasonKind[item.reason.kind] ?? 0) + 1
            }
            posthog.capture('replay_vision_highlight_feed_viewed', {
                ...servedListProperties(values.feedLoad, items),
                clip_count: items.length,
                scanner_count: new Set(items.map((item) => item.observation.scanner_id)).size,
                reason_kind_counts: countByReasonKind,
                categories: values.categories,
                // Which dead end the reader hit, so the empty screens can be counted and ranked
                // against each other instead of only showing up as a clip count of zero.
                ...(items.length === 0 ? { empty_reason: values.emptyReason ?? 'unresolved' } : {}),
            })
        },
    })),

    selectors({
        // A stored value can name a kind this build no longer knows, and hiding every kind leaves nothing to show.
        categories: [
            (s) => [s.hiddenCategories],
            (hiddenCategories: string[]): HighlightFeedCategoryEnumApi[] => {
                const shown = FEED_CATEGORIES.filter((category) => !hiddenCategories.includes(category))
                return shown.length > 0 ? shown : FEED_CATEGORIES
            },
        ],
        /** Null until the scanner list answers, so the scope tabs never flash in and out. */
        hasOwnScanners: [
            (s) => [s.scanners, s.scannersLoading, s.user],
            (scanners: ReplayScannerApi[], scannersLoading: boolean, user: UserType | null): boolean | null =>
                // A reload keeps the last answer, so only the first load reads as unknown.
                scannersLoading && scanners.length === 0
                    ? null
                    : !!user && scanners.some((scanner) => scanner.created_by?.id === user.id),
        ],
        // A choice persisted while the viewer still had scanners must not narrow a feed whose tabs are hidden.
        scopedToMine: [
            (s) => [s.onlyMyScanners, s.hasOwnScanners],
            (onlyMyScanners: boolean, hasOwnScanners: boolean | null): boolean =>
                onlyMyScanners && hasOwnScanners !== false,
        ],
        /** Null until both probes answer, so an empty screen is never drawn from unresolved data. */
        emptyReason: [
            (s) => [s.scanners, s.scannersLoading, s.quota, s.quotaLoading, s.scopedToMine],
            (
                scanners: ReplayScannerApi[],
                scannersLoading: boolean,
                quota: VisionQuotaApi | null,
                quotaLoading: boolean,
                scopedToMine: boolean
            ): HighlightFeedEmptyReason | null =>
                scannersLoading || quotaLoading
                    ? null
                    : // The feed does not say anything about recording being off; that card lives in the picks column.
                      resolveHighlightFeedEmptyReason({
                          scanners,
                          quota,
                          sessionRecordingOptIn: null,
                          hasFeedFilters: scopedToMine,
                      }),
        ],
    }),

    subscriptions(({ actions }) => ({
        // Reloads on a tab switch, and when the scanner list answers after a load and the stored scope stops applying.
        scopedToMine: (scopedToMine: boolean, previous: boolean | undefined) => {
            if (previous !== undefined && scopedToMine !== previous) {
                actions.loadFeed()
            }
        },
    })),

    // The tab content mounts only while the tab is active, so mount is the fetch signal.
    afterMount(({ actions, cache }) => {
        cache.impressions = new HighlightFeedImpressions('feed_tab', (load, ids) =>
            recordFeedImpressions(load.feedLoadId, ids)
        )
        // Not paused on hide: hiding is when the batch must go out.
        cache.disposables.add(cache.impressions.flushOnHideAndUnmount, 'impressionsFlush', { pauseOnPageHidden: false })
        actions.loadFeed()
    }),
])
