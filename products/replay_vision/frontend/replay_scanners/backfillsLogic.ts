export const backfillsLogic = kea<backfillsLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'backfillsLogic']),
    props({} as BackfillsLogicProps),
    key((props) => props.scannerId),

    actions({
        loadBackfills: (background = false) => ({ background }),
        loadBackfillsSuccess: (backfills: ReplayScannerBackfillApi[]) => ({ backfills }),
        loadBackfillsFailure: true,
        requestEstimate: (windowStart: string, windowEnd: string) => ({ windowStart, windowEnd }),
        requestEstimateSuccess: (estimate: BackfillEstimateResponseApi) => ({ estimate }),
        requestEstimateFailure: true,
        clearEstimate: true,
        createBackfill: (windowStart: string, windowEnd: string) => ({ windowStart, windowEnd }),
        createBackfillDone: true,
        cancelBackfill: (id: string) => ({ id }),
        resumeBackfill: (id: string) => ({ id }),
        transitionBackfillDone: (id: string) => ({ id }),
        setWindowRange: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
    }),

    reducers({
        backfills: [
            [] as ReplayScannerBackfillApi[],
            {
                loadBackfillsSuccess: (_, { backfills }) => backfills,
            },
        ],
        backfillsLoading: [
            false,
            {
                loadBackfills: (state, { background }) => (background ? state : true),
                loadBackfillsSuccess: () => false,
                loadBackfillsFailure: () => false,
            },
        ],
        estimate: [
            null as BackfillEstimateResponseApi | null,
            {
                requestEstimate: () => null,
                requestEstimateSuccess: (_, { estimate }) => estimate,
                clearEstimate: () => null,
                createBackfillDone: () => null,
            },
        ],
        estimateLoading: [
            false,
            {
                requestEstimate: () => true,
                requestEstimateSuccess: () => false,
                requestEstimateFailure: () => false,
                clearEstimate: () => false,
            },
        ],
        creatingBackfill: [
            false,
            {
                createBackfill: () => true,
                createBackfillDone: () => false,
            },
        ],
        windowDateFrom: [null as string | null, { setWindowRange: (_, { dateFrom }) => dateFrom }],
        windowDateTo: [null as string | null, { setWindowRange: (_, { dateTo }) => dateTo }],
        transitioningIds: [
            [] as string[],
            {
                cancelBackfill: (state, { id }) => [...state, id],
                resumeBackfill: (state, { id }) => [...state, id],
                transitionBackfillDone: (state, { id }) => state.filter((i) => i !== id),
            },
        ],
    }),

    listeners(({ actions, props, values, cache }) => ({
        loadBackfills: async () => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                return
            }
            try {
                const response = await visionScannersBackfillsList(String(teamId), props.scannerId, { limit: 100 })
                actions.loadBackfillsSuccess(response.results ?? [])
            } catch {
                actions.loadBackfillsFailure()
                lemonToast.error('Couldn’t load backfills. Refresh the page to try again.')
            }
        },
        loadBackfillsSuccess: () => {
            if (values.backfills.some((b) => b.status === 'running')) {
                cache.disposables.add(() => {
                    const timerId = window.setTimeout(() => actions.loadBackfills(true), ACTIVE_POLL_INTERVAL_MS)
                    return () => window.clearTimeout(timerId)
                }, 'backfillPoll')
            } else {
                cache.disposables.dispose('backfillPoll')
            }
        },
        requestEstimate: async ({ windowStart, windowEnd }, breakpoint) => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                return
            }
            await breakpoint(250)
            try {
                const estimate = await visionScannersBackfillsEstimateCreate(String(teamId), props.scannerId, {
                    window_start: windowStart,
                    window_end: windowEnd,
                })
                breakpoint()
                actions.requestEstimateSuccess(estimate)
            } catch (error: any) {
                breakpoint()
                actions.requestEstimateFailure()
                lemonToast.error(estimateErrorMessage(error))
            }
        },
        createBackfill: async ({ windowStart, windowEnd }) => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                actions.createBackfillDone()
                return
            }
            try {
                await visionScannersBackfillsCreate(String(teamId), props.scannerId, {
                    window_start: windowStart,
                    window_end: windowEnd,
                })
                lemonToast.success('Backfill started')
                actions.loadBackfills()
            } catch (error: any) {
                lemonToast.error(estimateErrorMessage(error))
            } finally {
                actions.createBackfillDone()
            }
        },
        cancelBackfill: async ({ id }) => {
            const teamId = teamLogic.values.currentTeamId
            try {
                if (teamId) {
                    await visionScannersBackfillsCancelCreate(String(teamId), props.scannerId, id)
                    actions.loadBackfills(true)
                }
            } catch {
                lemonToast.error('Couldn’t cancel the backfill. Try again.')
            } finally {
                actions.transitionBackfillDone(id)
            }
        },
        resumeBackfill: async ({ id }) => {
            const teamId = teamLogic.values.currentTeamId
            try {
                if (teamId) {
                    await visionScannersBackfillsResumeCreate(String(teamId), props.scannerId, id)
                    actions.loadBackfills(true)
                }
            } catch (error: any) {
                lemonToast.error(estimateErrorMessage(error, 'Couldn’t resume the backfill. Try again.'))
            } finally {
                actions.transitionBackfillDone(id)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadBackfills()
    }),
])

function estimateErrorMessage(error: any, fallback = 'Something went wrong. Try again.'): string {
    const detail = error?.data?.detail ?? (Array.isArray(error?.data) ? error.data[0] : null)
    return typeof detail === 'string' && detail.length > 0 ? detail : fallback
}
