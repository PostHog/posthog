import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import {
    visionScannersBackfillsCancelCreate,
    visionScannersBackfillsCreate,
    visionScannersBackfillsEstimateCreate,
    visionScannersBackfillsList,
    visionScannersBackfillsResumeCreate,
} from '../generated/api'
import type { BackfillEstimateResponseApi, ReplayScannerBackfillApi } from '../generated/api.schemas'

export interface BackfillsLogicProps {
    scannerId: string
}

// Keeps progress counts fresh while a backfill is dispatching, without hammering the API when idle.
const ACTIVE_POLL_INTERVAL_MS = 10_000

export function isBackfillActive(backfill: ReplayScannerBackfillApi): boolean {
    return backfill.status === 'running' || backfill.status === 'paused_quota'
}

