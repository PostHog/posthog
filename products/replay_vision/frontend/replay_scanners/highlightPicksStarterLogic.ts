export const highlightPicksStarterLogic: LogicWrapper<highlightPicksStarterLogicType> =
    kea<highlightPicksStarterLogicType>([
        props({} as HighlightPicksStarterLogicProps),
        key((props) => props.logicKey),
        path((key) => ['products', 'replay_vision', 'frontend', 'replay_scanners', 'highlightPicksStarterLogic', key]),

        connect(() => ({
            values: [teamLogic, ['currentTeamId'], visionQuotaLogic, ['freeCreditsLeft']],
        })),

        actions({
            setBudget: (budget: number) => ({ budget }),
            chooseBudget: (budgetChosen: boolean) => ({ budgetChosen }),
            startScanner: true,
            scannerStarted: (scanner: ReplayScannerApi, sessionIds: string[], teamId: number) => ({
                scanner,
                sessionIds,
                teamId,
            }),
            startFailed: (message: string) => ({ message }),
            pollBurst: true,
            burstPolled: (counts: BurstCounts) => ({ counts }),
            burstSettled: (stalled: boolean = false) => ({ stalled }),
            feedWindowElapsed: true,
            resumeBurst: true,
            showScannedAnyway: true,
            scannedAnywayLoaded: (observations: ReplayObservationApi[]) => ({ observations }),
            reset: true,
        }),

        reducers({
            budget: [
                BUDGET_PRESETS[1] as number,
                {
                    setBudget: (_, { budget }) => budget,
                },
            ],
            budgetChosen: [
                false,
                {
                    chooseBudget: (_, { budgetChosen }) => budgetChosen,
                    reset: () => false,
                },
            ],
            starting: [
                false,
                {
                    startScanner: () => true,
                    scannerStarted: () => false,
                    startFailed: () => false,
                },
            ],
            startError: [
                null as string | null,
                {
                    startScanner: () => null,
                    startFailed: (_, { message }) => message,
                    reset: () => null,
                },
            ],
            startedScanner: [
                null as ReplayScannerApi | null,
                { persist: true, storageKey: 'replay-vision.highlight-picks-starter.startedScanner' },
                {
                    scannerStarted: (_, { scanner }) => scanner,
                    reset: () => null,
                },
            ],
            burstSessionIds: [
                [] as string[],
                { persist: true, storageKey: 'replay-vision.highlight-picks-starter.burstSessionIds' },
                {
                    scannerStarted: (_, { sessionIds }) => sessionIds,
                    reset: () => [],
                },
            ],
            burstCounts: [
                { pending: 0, succeeded: 0, failed: 0 } as BurstCounts,
                {
                    scannerStarted: (_, { sessionIds }) => ({ pending: sessionIds.length, succeeded: 0, failed: 0 }),
                    burstPolled: (_, { counts }) => counts,
                    reset: () => ({ pending: 0, succeeded: 0, failed: 0 }),
                },
            ],
            burstDone: [
                false,
                { persist: true, storageKey: 'replay-vision.highlight-picks-starter.burstDone' },
                {
                    scannerStarted: (_, { sessionIds }) => sessionIds.length === 0,
                    burstSettled: () => true,
                    reset: () => false,
                },
            ],
            burstStartedAt: [
                0,
                { persist: true, storageKey: 'replay-vision.highlight-picks-starter.burstStartedAt' },
                {
                    scannerStarted: () => Date.now(),
                    reset: () => 0,
                },
            ],
            burstTeamId: [
                null as number | null,
                { persist: true, storageKey: 'replay-vision.highlight-picks-starter.burstTeamId' },
                {
                    scannerStarted: (_, { teamId }) => teamId,
                    reset: () => null,
                },
            ],
            burstStalled: [
                false,
                {
                    scannerStarted: () => false,
                    burstSettled: (_, { stalled }) => stalled,
                    reset: () => false,
                },
            ],
            feedWindowOpen: [
                false,
                {
                    burstSettled: () => true,
                    feedWindowElapsed: () => false,
                    reset: () => false,
                },
            ],
            scannedAnyway: [
                null as ReplayObservationApi[] | null,
                {
                    scannedAnywayLoaded: (_, { observations }) => observations,
                    reset: () => null,
                },
            ],
        }),

        selectors(({ props }) => ({
            candidateRecordings: [
                () => [
                    props.playlistLogicProps
                        ? sessionRecordingsPlaylistLogic(props.playlistLogicProps).selectors.sessionRecordings
                        : () => [],
                ],
                (recordings: SessionRecordingType[]): CandidateRecording[] => recordings,
            ],
            creditsPerObservation: [() => [], (): number => OBSERVATION_CREDITS_BY_MODEL[DEFAULT_MODEL]],
            freeAvailable: [
                (s) => [s.freeCreditsLeft, s.creditsPerObservation],
                (freeCreditsLeft: number | null, creditsPerObservation: number): boolean =>
                    starterSpendMode(freeCreditsLeft, creditsPerObservation) === 'free',
            ],
            spendMode: [
                (s) => [s.freeAvailable, s.budgetChosen],
                (freeAvailable: boolean, budgetChosen: boolean): StarterSpendMode =>
                    freeAvailable && !budgetChosen ? 'free' : 'budget',
            ],
            burstPlan: [
                (s) => [s.candidateRecordings, s.creditsPerObservation, s.spendMode, s.freeCreditsLeft, s.budget],
                (
                    candidateRecordings: CandidateRecording[],
                    creditsPerObservation: number,
                    spendMode: StarterSpendMode,
                    freeCreditsLeft: number | null,
                    budget: number
                ): BurstPlan =>
                    planBurst(candidateRecordings, creditsPerObservation, spendMode, freeCreditsLeft, budget),
            ],
        })),

        listeners(({ actions, values, props, cache }) => ({
            startScanner: async () => {
                const teamId = values.currentTeamId
                if (!teamId) {
                    actions.startFailed('Could not create the scanner. Try again.')
                    return
                }
                const template = QUICKSTART_SCANNER
                const query = { kind: NodeKind.RecordingsQuery }
                let estimatedAtFullRate: number | null =
                    highlightPicksVolumeLogic.findMounted()?.values.volumeEstimate?.estimated_observations_per_month ??
                    null
                if (estimatedAtFullRate === null) {
                    try {
                        const estimate = await visionScannersEstimateCreate(String(teamId), {
                            query,
                            sampling_rate: 1,
                            model: DEFAULT_MODEL,
                        })
                        estimatedAtFullRate = estimate.estimated_observations_per_month
                    } catch {
                        estimatedAtFullRate = null
                    }
                }
                const samplingRate = samplingRateForTarget(estimatedAtFullRate, TARGET_MONTHLY_SCANS)
                const free = values.spendMode === 'free'
                const plan = values.burstPlan
                let scanner: ReplayScannerApi
                try {
                    scanner = await visionScannersCreate(
                        String(teamId),
                        scannerToApiBody({
                            name: template.name,
                            description: template.description,
                            scanner_type: template.scanner_type,
                            scanner_config: structuredClone(template.scanner_config),
                            model: DEFAULT_MODEL,
                            provider: DEFAULT_PROVIDER,
                            enabled: true,
                            sampling_rate: samplingRate,
                            sampling_mode: 'balanced',
                            query,
                            tags: [],
                            free_only: free,
                            credit_limit: free ? FREE_SCANNER_CREDIT_LIMIT : values.budget,
                            creation_method: 'template',
                        })
                    )
                } catch {
                    posthog.capture('replay_vision_highlight_picks_starter_failed', {
                        template: template.key,
                        step: 'create',
                    })
                    actions.startFailed('Could not create the scanner. Try again.')
                    return
                }
                let started: string[] = []
                if (plan.sessionIds.length > 0) {
                    try {
                        const response = await visionScannersBulkObserveCreate(String(teamId), scanner.id, {
                            session_ids: plan.sessionIds,
                        })
                        started = response.results
                            .filter(
                                (result) =>
                                    result.scan_outcome === 'started' || result.scan_outcome === 'already_running'
                            )
                            .map((result) => result.session_id)
                    } catch {
                        started = []
                    }
                }
                posthog.capture('replay_vision_highlight_picks_starter_started', {
                    template: template.key,
                    scanner_id: scanner.id,
                    spend_mode: values.spendMode,
                    sampling_rate: samplingRate,
                    burst_planned: plan.sessionIds.length,
                    burst_started: started.length,
                })
                visionScannersListLogic.findMounted()?.actions.loadScanners()
                visionQuotaLogic.findMounted()?.actions.loadQuota()
                highlightPicksLogic.findMounted(props)?.actions.adoptPicksMode()
                if (!free) {
                    const showUsd = visionQuotaLogic.findMounted()?.values.showUsd ?? false
                    lemonToast.success(
                        `${scanner.name} created with a ${formatCreditsMaybeUsd(values.budget, showUsd)} monthly limit.`,
                        {
                            button: {
                                label: 'Change limit',
                                action: () => router.actions.push(urls.replayVision(scanner.id)),
                                dataAttr: 'vision-highlight-picks-starter-change-limit',
                            },
                        }
                    )
                }
                actions.scannerStarted(scanner, started, teamId)
            },
            scannerStarted: ({ sessionIds }) => {
                if (sessionIds.length > 0) {
                    actions.resumeBurst()
                }
            },
            resumeBurst: () => {
                let polls = 0
                cache.lastProgress = values.burstCounts.succeeded + values.burstCounts.failed
                cache.lastProgressAt = Date.now()
                actions.pollBurst()
                cache.disposables.add(() => {
                    const timer = window.setInterval(() => {
                        polls += 1
                        if (polls > BURST_POLL_MAX) {
                            actions.burstSettled(true)
                            return
                        }
                        actions.pollBurst()
                    }, BURST_POLL_MS)
                    return () => clearInterval(timer)
                }, 'burst-poll')
            },
            pollBurst: async (_, breakpoint) => {
                const teamId = values.currentTeamId
                const scanner = values.startedScanner
                if (!teamId || !scanner) {
                    return
                }
                const burst = new Set(values.burstSessionIds)
                const response = await visionScannersObservationsList(String(teamId), scanner.id, {
                    limit: BURST_MAX_RECORDINGS,
                    order_by: '-created_at',
                })
                breakpoint()
                const rows = response.results.filter((row) => burst.has(row.session_id))
                const counts: BurstCounts = {
                    pending: rows.filter((row) => row.status === 'pending' || row.status === 'running').length,
                    succeeded: rows.filter((row) => row.status === 'succeeded').length,
                    failed: rows.filter((row) => row.status === 'failed' || row.status === 'ineligible').length,
                }
                actions.burstPolled(counts)
                highlightPicksLogic.findMounted(props)?.actions.loadPicks()
                const progress = counts.succeeded + counts.failed
                if (progress !== cache.lastProgress) {
                    cache.lastProgress = progress
                    cache.lastProgressAt = Date.now()
                }
                if (counts.pending === 0 && rows.length >= burst.size) {
                    actions.burstSettled(false)
                } else if (Date.now() - (cache.lastProgressAt ?? Date.now()) > BURST_STALL_MS) {
                    actions.burstSettled(true)
                }
            },
            burstSettled: ({ stalled }) => {
                cache.disposables.dispose('burst-poll')
                let refreshes = 0
                cache.disposables.add(() => {
                    const timer = window.setInterval(() => {
                        refreshes += 1
                        highlightPicksLogic.findMounted(props)?.actions.loadPicks()
                        if (refreshes >= SETTLED_REFRESH_MAX) {
                            actions.feedWindowElapsed()
                        }
                    }, SETTLED_REFRESH_MS)
                    return () => clearInterval(timer)
                }, 'settled-refresh')
                const picksLogicMounted = highlightPicksLogic.findMounted(props)
                if (
                    values.startedScanner &&
                    values.burstCounts.succeeded > 0 &&
                    picksLogicMounted &&
                    picksLogicMounted.values.effectiveListMode !== 'picks'
                ) {
                    lemonToast.info(
                        `${values.startedScanner.name} finished scanning ${pluralize(values.burstCounts.succeeded, 'recording')}.`,
                        {
                            button: {
                                label: 'Show highlights',
                                action: () => picksLogicMounted.actions.setListMode('picks'),
                                dataAttr: 'vision-highlight-picks-starter-finished-toast',
                            },
                        }
                    )
                }
                posthog.capture('replay_vision_highlight_picks_starter_settled', {
                    scanner_id: values.startedScanner?.id,
                    stalled,
                    pending: values.burstCounts.pending,
                    succeeded: values.burstCounts.succeeded,
                    failed: values.burstCounts.failed,
                    picks_count: highlightPicksLogic.findMounted(props)?.values.picks?.length ?? 0,
                })
            },
            showScannedAnyway: async (_, breakpoint) => {
                const teamId = values.currentTeamId
                const scanner = values.startedScanner
                if (!teamId || !scanner) {
                    return
                }
                const response = await visionScannersObservationsList(String(teamId), scanner.id, {
                    limit: BURST_MAX_RECORDINGS,
                    order_by: '-created_at',
                    status: 'succeeded',
                })
                breakpoint()
                actions.scannedAnywayLoaded(response.results)
            },
            reset: () => {
                cache.disposables.dispose('burst-poll')
                cache.disposables.dispose('settled-refresh')
            },
        })),

        afterMount(({ actions, values }) => {
            if (!values.startedScanner) {
                return
            }
            const stale =
                values.burstDone ||
                values.burstTeamId !== values.currentTeamId ||
                Date.now() - values.burstStartedAt > BURST_RESUME_MAX_AGE_MS
            if (stale) {
                actions.reset()
                return
            }
            actions.resumeBurst()
        }),
    ])
