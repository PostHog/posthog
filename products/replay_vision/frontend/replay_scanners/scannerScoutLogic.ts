/** Everything the scout form edits, in both create and settings mode. */
export interface ScannerScoutForm {
    name: string
    body: string
    cron: string
    /** Slack rides on the scout config: the platform posts each report it files. */
    outputDestinations: SignalScoutOutputDestinationsApi
    /** Empty means no webhook; the CDP destination is created, updated, or removed to match. */
    webhookUrl: string
}

/** Where a scout's digests are delivered, read back off its CDP destinations. `skillName` is what
 * the form checks before seeding: a failed load leaves the previous scout's value in place, and
 * without it that value would be seeded into, and then saved onto, a different scout. */
export interface ScoutDelivery {
    skillName: string
    webhook: { id: string; url: string } | null
}

/** One scout's instructions, tagged with the scout they belong to for the same reason. */
export interface ScoutPrompt {
    skillName: string
    body: string
}

function inputValue(inputs: unknown, key: string): unknown {
    return (inputs as Record<string, { value?: unknown }> | undefined)?.[key]?.value
}

/** The destination carrying this scout's digests, read from the id its config records in
 * `output_destinations.webhook`. */
async function findScoutDelivery(
    projectId: string,
    skillName: string,
    outputDestinations: SignalScoutOutputDestinationsApi | null | undefined
): Promise<Omit<ScoutDelivery, 'skillName'>> {
    const webhookId = outputDestinations?.webhook?.hog_function_id
    if (!webhookId) {
        return { webhook: null }
    }
    // The destination is fetched by the id the config records, so this costs one request whatever
    // else the project holds. It also can't adopt someone else's destination by resemblance.
    try {
        const webhook = await hogFunctionsRetrieve(projectId, webhookId)
        // The id alone is not proof this destination is ours: `output_destinations` is caller-
        // writable, so a config can name any destination in the project, and acting on it would use
        // this reader's permissions to overwrite or delete someone else's.
        if (webhook.deleted || !isScoutDestination(webhook, skillName)) {
            return { webhook: null }
        }
        return { webhook: { id: webhookId, url: String(inputValue(webhook.inputs, 'url') ?? '') } }
    } catch (error: any) {
        if (error?.status === 404) {
            // Deleted in Data pipelines. Treat it as absent so the next save provisions a new one.
            return { webhook: null }
        }
        throw error
    }
}

