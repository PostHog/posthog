export const REPLAY_VISION_INTENT_DWELL_MS = 15000

/** `all`, `search`, `usage`, or a scanner id. */
export type VisionHomeView = string

export interface HighlightCounts {
    total: number
    byScanner: Record<string, number>
}

// Healthy scanners lead the picker, so the ones that need fixing never crowd out the ones worth reading.
const HEALTHY_KINDS: ReadonlySet<ScannerStatus['kind']> = new Set([
    'running',
    'throttled',
    'starting',
    'delayed',
    'no_matches',
])

export function isProblemStatus(status: ScannerStatus): boolean {
    return !HEALTHY_KINDS.has(status.kind)
}

/** True when the scanner cannot have found anything new, so its view shows a note in place of stats. */
export function scannerFeedIsIdle(kind: ScannerStatus['kind'] | undefined): kind is 'off' | 'starting' {
    return kind === 'off' || kind === 'starting'
}

/** Every observation the scanner made, not only its highlights. */
export function scannerObservationsUrl(scannerId: string): string {
    return combineUrl(urls.replayVision(scannerId), { tab: ReplayScannerTab.Observations }).url
}

/** Reads the home view from the URL. `?tab=highlights` and `?tab=scanners` are old links to what is now the default view. */
export function homeViewFromSearchParams(searchParams: Record<string, any>): VisionHomeView {
    // Search keeps its scanner scope in `scanner` too, so the tab wins.
    if (searchParams.tab === 'search' || searchParams.tab === 'usage') {
        return searchParams.tab
    }
    return typeof searchParams.scanner === 'string' && searchParams.scanner ? searchParams.scanner : 'all'
}

