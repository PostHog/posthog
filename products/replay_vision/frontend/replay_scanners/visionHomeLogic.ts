/** The Replay vision home: which scanners the menu offers, in what order, and how many highlights each holds. */
export const visionHomeLogic = kea<visionHomeLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'visionHomeLogic']),

    connect(() => ({
        values: [
            visionScannersListLogic,
            ['scanners', 'scannersLoading'],
            visionQuotaLogic,
            ['quota'],
            replayRecordingsLogic,
            ['recordingsBlock'],
            router,
            ['searchParams', 'location'],
            teamLogic,
            ['currentTeamId'],
        ],
        actions: [router, ['push'], visionScannersListLogic, ['loadScanners']],
    })),

    actions({
        setView: (view: VisionHomeView) => ({ view }),
        syncViewFromUrl: (view: VisionHomeView) => ({ view }),
        openBlockView: (view: 'newest-scanner' | 'usage') => ({ view }),
        loadHighlightCounts: true,
    }),

    loaders(() => ({
        highlightCounts: [
            null as HighlightCounts | null,
            {
                loadHighlightCounts: async (_, breakpoint) => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        return null
                    }
                    // One card is enough: the counts cover every page of the default window.
                    const response = await visionScannersHighlightFeedRetrieve(String(teamId), {
                        date_from: DEFAULT_FEED_DATE_FROM,
                        limit: 1,
                    })
                    breakpoint()
                    return {
                        total: response.highlight_count ?? 0,
                        byScanner: response.highlight_counts_by_scanner ?? {},
                    }
                },
            },
        ],
    })),

    reducers({
        // Set only while the home's own route is in the URL. A link out to a scanner page changes the URL a moment
        // before the scene changes, and reading that URL would flash the default feed.
        urlView: [
            'all' as VisionHomeView,
            {
                syncViewFromUrl: (_, { view }) => view,
            },
        ],
    }),

    selectors({
        view: [
            (s) => [s.urlView, s.scanners, s.scannersLoading],
            (
                urlView: visionHomeLogicValues['urlView'],
                scanners: visionHomeLogicValues['scanners'],
                scannersLoading: visionHomeLogicValues['scannersLoading']
            ): VisionHomeView => {
                const view = urlView
                // A link to a scanner that was deleted, or that the viewer can't read, lands on every highlight.
                const isScanner = view !== 'all' && view !== 'search' && view !== 'usage'
                const known = scanners.some((scanner: ReplayScannerApi) => scanner.id === view)
                return isScanner && !known && !scannersLoading ? 'all' : view
            },
        ],
        scannerStatuses: [
            (s) => [s.scanners, s.quota, s.recordingsBlock],
            (
                scanners: visionHomeLogicValues['scanners'],
                quota: visionHomeLogicValues['quota'],
                recordingsBlock: visionHomeLogicValues['recordingsBlock']
            ): Record<string, ScannerStatus> => {
                const quotaExhausted = quotaBannerState(quota).kind === 'exhausted'
                return Object.fromEntries(
                    scannersFromApi(scanners).map((scanner) => [
                        scanner.id,
                        scannerStatus(scanner, { quotaExhausted, drought: null, recordingsBlock }),
                    ])
                )
            },
        ],
        // Creation order keeps every scanner in the same place from one day to the next.
        homeScanners: [
            (s) => [s.scanners],
            (scanners: visionHomeLogicValues['scanners']): ReplayScanner[] =>
                scannersFromApi(scanners).sort((a, b) => (a.created_at ?? '').localeCompare(b.created_at ?? '')),
        ],
        pickerScanners: [
            (s) => [s.homeScanners, s.scannerStatuses],
            (
                homeScanners: visionHomeLogicValues['homeScanners'],
                scannerStatuses: visionHomeLogicValues['scannerStatuses']
            ): ReplayScanner[] =>
                [...homeScanners].sort(
                    (a, b) =>
                        Number(isProblemStatus(scannerStatuses[a.id])) - Number(isProblemStatus(scannerStatuses[b.id]))
                ),
        ],
        selectedScanner: [
            (s) => [s.view, s.homeScanners],
            (
                view: visionHomeLogicValues['view'],
                homeScanners: visionHomeLogicValues['homeScanners']
            ): ReplayScanner | null => homeScanners.find((scanner) => scanner.id === view) ?? null,
        ],
    }),

    listeners(({ values, actions }) => ({
        openBlockView: ({ view }) => {
            const newest = values.homeScanners[values.homeScanners.length - 1]
            actions.setView(view === 'usage' ? 'usage' : (newest?.id ?? 'all'))
        },
        // The view lives in the URL, so a link, a refresh and the back button all land on the same one.
        setView: ({ view }) => {
            const { scanner: _scanner, tab: _tab, ...rest } = values.searchParams
            actions.push(
                values.location.pathname,
                view === 'all'
                    ? rest
                    : view === 'search' || view === 'usage'
                      ? { ...rest, tab: view }
                      : { ...rest, scanner: view }
            )
        },
    })),

    subscriptions(({ actions, cache }) => ({
        // Starting and delayed end when a sweep tick finishes, which the home only sees by reloading the scanners.
        scannerStatuses: (statuses: Record<string, ScannerStatus>) => {
            if (Object.values(statuses).some((status) => status.kind === 'starting' || status.kind === 'delayed')) {
                cache.disposables.add(() => {
                    const timer = setInterval(() => {
                        actions.loadScanners()
                        actions.loadHighlightCounts()
                    }, STATUS_POLL_MS)
                    return () => clearInterval(timer)
                }, 'statusPoll')
            } else {
                cache.disposables.dispose('statusPoll')
            }
        },
        currentTeamId: (teamId: number | null, previous: number | null | undefined) => {
            if (previous !== undefined && teamId !== previous) {
                actions.loadHighlightCounts()
            }
        },
    })),

    urlToAction(({ actions }) => ({
        [urls.replayVision()]: (_, searchParams) => {
            actions.syncViewFromUrl(homeViewFromSearchParams(searchParams))
        },
    })),

    afterMount(({ actions, cache }) => {
        actions.loadHighlightCounts()
        // Shallow product intent: reading the home for a while is interest, and it's the only signal the
        // people who never create a scanner ever produce. Gated on dwell, because a bounce would otherwise
        // start the team's 30-day activation clock. A disposable, so the clock pauses while the tab is hidden.
        cache.disposables.add(() => {
            const timer = setTimeout(() => {
                // Dropped once fired, so a later hide and show does not register again.
                cache.disposables.dispose('replayVisionDwell')
                void addProductIntent({
                    product_type: ProductKey.REPLAY_VISION,
                    intent_context: ProductIntentContext.REPLAY_VISION_VIEWED,
                })
            }, REPLAY_VISION_INTENT_DWELL_MS)
            return () => clearTimeout(timer)
        }, 'replayVisionDwell')
    }),
])
