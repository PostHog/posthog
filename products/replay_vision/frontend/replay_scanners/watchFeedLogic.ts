export const DEFAULT_FEED_DATE_FROM: string = '-7d'

/** Which ranker ordered the loaded feed. Server-decided per team (the flag evaluates against the
 * team, not the viewer), so the client reads it from the response instead of checking the flag. */
export type WatchFeedRanker = WatchFeedResponseApi['ranker']

/** The ranker experiment's flag. The server decides its variant per project, so the client can't
 * evaluate it and reports the variant the response carries instead. */
const WATCH_FEED_RANKER_FLAG = 'vision-watch-feed-ranker'

function reportFiltered(values: watchFeedLogicValues): void {
    posthog.capture('replay_vision_watch_feed_filtered', {
        date_from: values.dateFrom,
        date_to: values.dateTo,
        scanner_type: values.scannerTypeFilter,
        scanner_ids_count: values.scannerIdsFilter.length,
        tags_count: values.tagsFilter.length,
        created_by_count: values.createdByFilter.length,
        has_search: values.search.trim().length > 0,
    })
}

/** Data for the What to watch tab: the window's most watchable observations, ranked server-side. */
export const watchFeedLogic = kea<watchFeedLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'watchFeedLogic']),

    connect(() => ({
        values: [
            tagsModel,
            ['tags as allTags'],
            // An empty feed cannot be explained from the feed alone: the reason lives in the fleet's
            // state and the org's budget.
            visionScannersListLogic,
            ['scanners', 'scannersLoading'],
            visionQuotaLogic,
            ['quota', 'quotaLoading'],
        ],
        actions: [tagsModel, ['loadTags']],
    })),

    actions({
        setDateRange: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setScannerTypeFilter: (scannerType: ScannerType | null) => ({ scannerType }),
        setSearch: (search: string) => ({ search }),
        setScannerIdsFilter: (scannerIds: string[]) => ({ scannerIds }),
        setTagsFilter: (tags: string[]) => ({ tags }),
        setCreatedByFilter: (userIds: string[]) => ({ userIds }),
        // Restores every shared-link filter at once so one request runs and every recipient sees the
        // same feed, regardless of the scanner/tag selections their browser remembered.
        restoreFeedFilters: (search: string, scannerIds: string[], tags: string[], createdBy: string[]) => ({
            search,
            scannerIds,
            tags,
            createdBy,
        }),
        clearFeedFilters: true,
        loadFeed: true,
        setFeedRanker: (ranker: WatchFeedRanker, variant: string | null) => ({ ranker, variant }),
        setFeedLoad: (load: WatchFeedLoad) => ({ load }),
        cardSeen: (item: WatchFeedItemApi, position: number) => ({ item, position }),
        dismissItem: (item: WatchFeedItemApi, position: number, reason: FeedDismissalReasonEnumApi | null) => ({
            item,
            position,
            reason,
        }),
        restoreItem: (item: WatchFeedItemApi, position: number) => ({ item, position }),
    }),

    loaders(({ values, actions }) => ({
        feedItems: [
            null as WatchFeedItemApi[] | null,
            {
                loadFeed: async (_, breakpoint) => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        // Reporting this as a successful empty result would read as "nothing to watch";
                        // fail instead so the tab shows the error state and a retry.
                        throw new Error('No current team')
                    }
                    const params: VisionScannersWatchFeedRetrieveParams = { date_from: values.dateFrom }
                    if (values.dateTo) {
                        params.date_to = values.dateTo
                    }
                    if (values.scannerTypeFilter) {
                        params.scanner_type = values.scannerTypeFilter
                    }
                    if (values.scannerIdsFilter.length > 0) {
                        params.scanner_ids = values.scannerIdsFilter.join(',')
                    }
                    if (values.tagsFilter.length > 0) {
                        params.tags = values.tagsFilter.join(',')
                    }
                    if (values.createdByFilter.length > 0) {
                        params.created_by = values.createdByFilter.join(',')
                    }
                    const trimmedSearch = values.search.trim()
                    if (trimmedSearch) {
                        params.search = trimmedSearch
                    }
                    const response = await visionScannersWatchFeedRetrieve(String(teamId), params)
                    // Drop out-of-order responses — the most recent filter change owns the feed.
                    breakpoint()
                    actions.setFeedRanker(response.ranker ?? 'weighted-score', response.ranker_variant ?? null)
                    actions.setFeedLoad(newWatchFeedLoad(response.ranker, response.results))
                    return response.results
                },
            },
        ],
    })),

    reducers({
        feedItems: {
            dismissItem: (state, { item }) => withoutFeedItem(state, item.observation.id),
            restoreItem: (state, { item, position }) => withFeedItemRestored(state, item, position),
        },
        feedLoad: [
            null as WatchFeedLoad | null,
            {
                setFeedLoad: (_, { load }) => load,
            },
        ],
        dateFrom: [
            DEFAULT_FEED_DATE_FROM,
            {
                setDateRange: (_, { dateFrom }) => dateFrom ?? DEFAULT_FEED_DATE_FROM,
            },
        ],
        dateTo: [
            null as string | null,
            {
                setDateRange: (_, { dateTo }) => dateTo,
            },
        ],
        scannerTypeFilter: [
            null as ScannerType | null,
            {
                setScannerTypeFilter: (_, { scannerType }) => scannerType,
                clearFeedFilters: () => null,
            },
        ],
        search: [
            '',
            {
                setSearch: (_, { search }) => search,
                restoreFeedFilters: (_, { search }) => search,
                clearFeedFilters: () => '',
            },
        ],
        // Persisted so a team with many scanners lands on the ones they follow instead of the whole
        // fleet on every visit. Keyed by team so a selection made on one team never carries into
        // another team's feed, where those scanner ids do not exist and would hide every result.
        // Browser-local until per-user pins exist, so it does not cross devices.
        scannerIdsFilter: [
            [] as string[],
            { persist: true, prefix: `${getCurrentTeamIdOrNone() ?? 'unknown'}__` },
            {
                setScannerIdsFilter: (_, { scannerIds }) => scannerIds,
                restoreFeedFilters: (_, { scannerIds }) => scannerIds,
                clearFeedFilters: () => [],
            },
        ],
        tagsFilter: [
            [] as string[],
            { persist: true, prefix: `${getCurrentTeamIdOrNone() ?? 'unknown'}__` },
            {
                setTagsFilter: (_, { tags }) => tags,
                restoreFeedFilters: (_, { tags }) => tags,
                clearFeedFilters: () => [],
            },
        ],
        createdByFilter: [
            [] as string[],
            { persist: true, prefix: `${getCurrentTeamIdOrNone() ?? 'unknown'}__` },
            {
                setCreatedByFilter: (_, { userIds }) => userIds,
                restoreFeedFilters: (_, { createdBy }) => createdBy,
                clearFeedFilters: () => [],
            },
        ],
        feedFailed: [
            false,
            {
                loadFeed: () => false,
                loadFeedFailure: () => true,
            },
        ],
        // Set from each response, so the card layout always matches the ranking it shows.
        feedRanker: [
            'weighted-score' as WatchFeedRanker,
            {
                setFeedRanker: (_, { ranker }) => ranker,
            },
        ],
        feedRankerVariant: [
            null as string | null,
            {
                setFeedRanker: (_, { variant }) => variant,
            },
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        setFeedLoad: ({ load }) => {
            cache.impressions.start(load)
        },
        cardSeen: ({ item, position }) => {
            cache.impressions.add(item, position)
        },
        dismissItem: async ({ item, position, reason }) => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                return
            }
            const loadId = values.feedLoad?.feedLoadId
            await dismissFeedItem({
                teamId,
                item,
                reason,
                properties: cardProperties(values.feedLoad, item, position, 'feed_tab'),
                restore: () => values.feedLoad?.feedLoadId === loadId && actions.restoreItem(item, position),
            })
        },
        setDateRange: () => {
            reportFiltered(values)
            actions.loadFeed()
        },
        setScannerTypeFilter: () => {
            reportFiltered(values)
            actions.loadFeed()
        },
        setScannerIdsFilter: () => {
            reportFiltered(values)
            actions.loadFeed()
        },
        setTagsFilter: () => {
            reportFiltered(values)
            actions.loadFeed()
        },
        setCreatedByFilter: () => {
            reportFiltered(values)
            actions.loadFeed()
        },
        clearFeedFilters: () => {
            reportFiltered(values)
            actions.loadFeed()
        },
        setSearch: async (_, breakpoint) => {
            // Debounce keystrokes; a shared-link restore loads once through restoreFeedFilters instead.
            await breakpoint(300)
            reportFiltered(values)
            actions.loadFeed()
        },
        restoreFeedFilters: () => {
            reportFiltered(values)
            actions.loadFeed()
        },
        loadFeedSuccess: ({ feedItems }) => {
            const items = feedItems ?? []
            // The click event reports the reason a reader picked; without this one nothing reports the mix
            // they were offered, so a ranking change cannot be read after it ships.
            const countByReasonKind: Record<string, number> = {}
            for (const item of items) {
                countByReasonKind[item.reason.kind] = (countByReasonKind[item.reason.kind] ?? 0) + 1
            }
            posthog.capture('replay_vision_watch_feed_viewed', {
                ...servedListProperties(values.feedLoad, items),
                clip_count: items.length,
                scanner_count: new Set(items.map((item) => item.observation.scanner_id)).size,
                reason_kind_counts: countByReasonKind,
                ranker: values.feedRanker,
                // The ranker experiment counts this event as its exposure, so it carries the project's variant.
                ...(values.feedRankerVariant
                    ? { [`$feature/${WATCH_FEED_RANKER_FLAG}`]: values.feedRankerVariant }
                    : {}),
                signal_share: items.length > 0 ? (countByReasonKind.signal_emitted ?? 0) / items.length : 0,
                // Which dead end the reader hit, so the empty screens can be counted and ranked
                // against each other instead of only showing up as a clip count of zero.
                ...(items.length === 0 ? { empty_reason: values.emptyReason ?? 'unresolved' } : {}),
            })
        },
    })),

    selectors({
        /** Null until both probes answer, so an empty screen is never drawn from unresolved data. */
        emptyReason: [
            (s) => [s.scanners, s.scannersLoading, s.quota, s.quotaLoading, s.hasFeedFilters],
            (
                scanners: ReplayScannerApi[],
                scannersLoading: boolean,
                quota: VisionQuotaApi | null,
                quotaLoading: boolean,
                hasFeedFilters: boolean
            ): WatchFeedEmptyReason | null =>
                scannersLoading || quotaLoading
                    ? null
                    : // The feed does not say anything about recording being off; that card lives in the picks column.
                      resolveWatchFeedEmptyReason({ scanners, quota, sessionRecordingOptIn: null, hasFeedFilters }),
        ],
        hasFeedFilters: [
            (s) => [s.scannerIdsFilter, s.tagsFilter, s.createdByFilter, s.scannerTypeFilter, s.search],
            (
                scannerIds: string[],
                tags: string[],
                createdBy: string[],
                scannerType: ScannerType | null,
                search: string
            ): boolean =>
                scannerIds.length > 0 ||
                tags.length > 0 ||
                createdBy.length > 0 ||
                !!scannerType ||
                search.trim().length > 0,
        ],
        tagOptions: [
            (s) => [s.allTags, s.tagsFilter],
            (allTags: string[], tagsFilter: string[]): { value: string; label: string }[] =>
                // Keep a tag restored from a shared link selectable even when the team list doesn't know it.
                Array.from(new Set([...allTags.filter((tag) => !tag.includes(',')), ...tagsFilter]))
                    .sort()
                    .map((tag) => ({ value: tag, label: tag })),
        ],
    }),

    trackedActionToUrl(({ values }) => {
        const buildUrl = (): [string, Record<string, string | undefined>, undefined, { replace: true }] => [
            urls.replayVision(),
            {
                ...router.values.searchParams,
                feed_search: values.search.trim() || undefined,
                feed_scanners: csvParam(values.scannerIdsFilter),
                feed_tags: csvParam(values.tagsFilter),
                feed_created_by: csvParam(values.createdByFilter),
            },
            undefined,
            { replace: true },
        ]
        return {
            setSearch: buildUrl,
            setScannerIdsFilter: buildUrl,
            setTagsFilter: buildUrl,
            setCreatedByFilter: buildUrl,
            clearFeedFilters: buildUrl,
        }
    }),

    urlToAction(({ actions, values }) => ({
        [urls.replayVision()]: (_, searchParams) => {
            // A link that carries any feed_* param is a full filter snapshot, so restore all of them and
            // clear the ones it omits — otherwise the reader's remembered scanner/tag picks would leak
            // in and the same link would show different feeds to different people. A link with no feed_*
            // param leaves those remembered picks alone rather than widening the feed to the whole fleet.
            const hasFeedParams =
                searchParams.feed_search !== undefined ||
                searchParams.feed_scanners !== undefined ||
                searchParams.feed_tags !== undefined ||
                searchParams.feed_created_by !== undefined
            if (!hasFeedParams) {
                return
            }
            const search = typeof searchParams.feed_search === 'string' ? searchParams.feed_search : ''
            const scanners = parseCsvParam(searchParams.feed_scanners)
            const tags = parseCsvParam(searchParams.feed_tags)
            const createdBy = parseCsvParam(searchParams.feed_created_by)
            const unchanged =
                search === values.search &&
                objectsEqual(scanners, values.scannerIdsFilter) &&
                objectsEqual(tags, values.tagsFilter) &&
                objectsEqual(createdBy, values.createdByFilter)
            if (!unchanged) {
                actions.restoreFeedFilters(search, scanners, tags, createdBy)
            }
        },
    })),

    // The tab content mounts only while the tab is active, so mount is the fetch signal.
    afterMount(({ actions, cache }) => {
        cache.impressions = new WatchFeedImpressions('feed_tab')
        // Not paused on hide: hiding is when the batch must go out.
        cache.disposables.add(cache.impressions.flushOnHideAndUnmount, 'impressionsFlush', { pauseOnPageHidden: false })
        actions.loadFeed()
        // tagsModel is lazy; load it so the tag filter isn't empty on a direct visit.
        actions.loadTags()
    }),
])
