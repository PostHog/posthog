export const DEFAULT_FEED_DATE_FROM: string = '-7d'
export const FEED_PAGE_SIZE = 20

/** Which ranker ordered the loaded feed. Server-decided per team (the flag evaluates against the
 * team, not the viewer), so the client reads it from the response instead of checking the flag. */
export type WatchFeedRanker = WatchFeedResponseApi['ranker']

/** The ranker experiment's flag. The server decides its variant per project, so the client can't
 * evaluate it and reports the variant the response carries instead. */
const WATCH_FEED_RANKER_FLAG = 'vision-watch-feed-ranker'

function feedParams(values: watchFeedLogicValues): VisionScannersWatchFeedRetrieveParams {
    const params: VisionScannersWatchFeedRetrieveParams = { date_from: values.dateFrom, limit: FEED_PAGE_SIZE }
    if (values.onlyMyScanners && values.user) {
        params.created_by = String(values.user.id)
    }
    return params
}

function reportFiltered(values: watchFeedLogicValues): void {
    posthog.capture('replay_vision_watch_feed_filtered', {
        date_from: values.dateFrom,
        only_my_scanners: values.onlyMyScanners,
    })
}

/** Data for the What to watch tab: the window's most watchable observations, ranked server-side. */
export const watchFeedLogic = kea<watchFeedLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'watchFeedLogic']),

    connect(() => ({
        values: [
            userLogic,
            ['user'],
            // An empty feed cannot be explained from the feed alone: the reason lives in the fleet's
            // state and the org's budget.
            visionScannersListLogic,
            ['scanners', 'scannersLoading'],
            visionQuotaLogic,
            ['quota', 'quotaLoading'],
        ],
    })),

    actions({
        setDateFrom: (dateFrom: string) => ({ dateFrom }),
        setOnlyMyScanners: (onlyMyScanners: boolean) => ({ onlyMyScanners }),
        loadFeed: true,
        setFeedRanker: (ranker: WatchFeedRanker, variant: string | null) => ({ ranker, variant }),
        setFeedLoad: (load: WatchFeedLoad) => ({ load }),
        extendFeedLoad: (load: WatchFeedLoad) => ({ load }),
        setFeedPaging: (hasMore: boolean, asOf: string | null, served: number) => ({ hasMore, asOf, served }),
        cardSeen: (item: WatchFeedItemApi, position: number) => ({ item, position }),
        dismissItem: (item: WatchFeedItemApi, position: number, reason: FeedDismissalReasonEnumApi | null) => ({
            item,
            position,
            reason,
        }),
        restoreItem: (item: WatchFeedItemApi, position: number) => ({ item, position }),
    }),

    loaders(({ values, actions, cache }) => ({
        feedItems: [
            null as WatchFeedItemApi[] | null,
            {
                loadFeed: async (_, breakpoint) => {
                    // Counts loads from the moment one starts, so a page requested for an older load is dropped.
                    cache.feedGeneration = (cache.feedGeneration ?? 0) + 1
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        // Reporting this as a successful empty result would read as "nothing to watch";
                        // fail instead so the tab shows the error state and a retry.
                        throw new Error('No current team')
                    }
                    const response = await visionScannersWatchFeedRetrieve(String(teamId), feedParams(values))
                    // Drop out-of-order responses — the most recent filter change owns the feed.
                    breakpoint()
                    actions.setFeedRanker(response.ranker ?? 'weighted-score', response.ranker_variant ?? null)
                    actions.setFeedLoad(newWatchFeedLoad(response.ranker, response.results))
                    actions.setFeedPaging(response.has_more ?? false, response.as_of ?? null, response.results.length)
                    return response.results
                },
                loadMoreFeed: async (_, breakpoint) => {
                    const teamId = teamLogic.values.currentTeamId
                    const load = values.feedLoad
                    if (!teamId || !load || !values.feedHasMore || !values.feedAsOf) {
                        return values.feedItems
                    }
                    // Counted against what the server returned, so neither a hidden card nor a deduplicated one shifts the next page.
                    const offset = values.feedServed
                    const generation = cache.feedGeneration
                    let response
                    try {
                        response = await visionScannersWatchFeedRetrieve(String(teamId), {
                            ...feedParams(values),
                            offset,
                            as_of: values.feedAsOf,
                        })
                    } catch (error) {
                        // A failure for a load the reader has since replaced must not stop paging the new one.
                        if (cache.feedGeneration !== generation) {
                            return values.feedItems
                        }
                        throw error
                    }
                    // A newer request for the next page supersedes this one, so the same page never appends twice.
                    breakpoint()
                    // A filter change while this page was in flight started a new load, which owns the feed now.
                    if (cache.feedGeneration !== generation || values.feedLoad?.feedLoadId !== load.feedLoadId) {
                        return values.feedItems
                    }
                    const page = response.results.filter((item) => !(item.observation.id in load.positions))
                    actions.extendFeedLoad(withNextPage(load, page))
                    // An empty page cannot advance the offset, so it ends paging rather than repeating the request.
                    actions.setFeedPaging(
                        (response.has_more ?? false) && response.results.length > 0,
                        response.as_of ?? null,
                        offset + response.results.length
                    )
                    posthog.capture('replay_vision_watch_feed_page_loaded', {
                        ...servedListProperties(values.feedLoad, page),
                        offset,
                        clip_count: page.length,
                        has_more: response.has_more,
                    })
                    return [...(values.feedItems ?? []), ...page]
                },
            },
        ],
    })),

    reducers({
        feedItems: {
            dismissItem: (state, { item }) => withoutFeedItem(state, item.observation.id),
            restoreItem: (state, { item, position }) => withFeedItemRestored(state, item, position),
        },
        feedLoad: [
            null as WatchFeedLoad | null,
            {
                setFeedLoad: (_, { load }) => load,
                extendFeedLoad: (_, { load }) => load,
            },
        ],
        feedHasMore: [
            false,
            {
                loadFeed: () => false,
                setFeedPaging: (_, { hasMore }) => hasMore,
            },
        ],
        feedAsOf: [
            null as string | null,
            {
                loadFeed: () => null,
                setFeedPaging: (_, { asOf }) => asOf,
            },
        ],
        feedServed: [
            0,
            {
                loadFeed: () => 0,
                setFeedPaging: (_, { served }) => served,
            },
        ],
        feedMoreFailed: [
            false,
            {
                loadFeed: () => false,
                loadMoreFeed: () => false,
                loadMoreFeedFailure: () => true,
            },
        ],
        dateFrom: [
            DEFAULT_FEED_DATE_FROM,
            {
                setDateFrom: (_, { dateFrom }) => dateFrom,
            },
        ],
        // Keyed by team, so the choice made on one team does not carry into another team's feed.
        onlyMyScanners: [
            false,
            { persist: true, prefix: `${getCurrentTeamIdOrNone() ?? 'unknown'}__` },
            {
                setOnlyMyScanners: (_, { onlyMyScanners }) => onlyMyScanners,
            },
        ],
        feedFailed: [
            false,
            {
                loadFeed: () => false,
                loadFeedFailure: () => true,
            },
        ],
        // Set from each response, so the card layout always matches the ranking it shows.
        feedRanker: [
            'weighted-score' as WatchFeedRanker,
            {
                setFeedRanker: (_, { ranker }) => ranker,
            },
        ],
        feedRankerVariant: [
            null as string | null,
            {
                setFeedRanker: (_, { variant }) => variant,
            },
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        setFeedLoad: ({ load }) => {
            cache.impressions.start(load)
        },
        extendFeedLoad: ({ load }) => {
            cache.impressions.extend(load)
        },
        cardSeen: ({ item, position }) => {
            cache.impressions.add(item, position)
        },
        dismissItem: async ({ item, position, reason }) => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                return
            }
            const loadId = values.feedLoad?.feedLoadId
            await dismissFeedItem({
                teamId,
                item,
                reason,
                properties: cardProperties(values.feedLoad, item, position, 'feed_tab'),
                restore: () => values.feedLoad?.feedLoadId === loadId && actions.restoreItem(item, position),
            })
        },
        setDateFrom: () => {
            reportFiltered(values)
            actions.loadFeed()
        },
        setOnlyMyScanners: () => {
            reportFiltered(values)
            actions.loadFeed()
        },
        loadFeedSuccess: ({ feedItems }) => {
            const items = feedItems ?? []
            // The click event reports the reason a reader picked; without this one nothing reports the mix
            // they were offered, so a ranking change cannot be read after it ships.
            const countByReasonKind: Record<string, number> = {}
            for (const item of items) {
                countByReasonKind[item.reason.kind] = (countByReasonKind[item.reason.kind] ?? 0) + 1
            }
            posthog.capture('replay_vision_watch_feed_viewed', {
                ...servedListProperties(values.feedLoad, items),
                clip_count: items.length,
                scanner_count: new Set(items.map((item) => item.observation.scanner_id)).size,
                reason_kind_counts: countByReasonKind,
                ranker: values.feedRanker,
                // The ranker experiment counts this event as its exposure, so it carries the project's variant.
                ...(values.feedRankerVariant
                    ? { [`$feature/${WATCH_FEED_RANKER_FLAG}`]: values.feedRankerVariant }
                    : {}),
                signal_share: items.length > 0 ? (countByReasonKind.signal_emitted ?? 0) / items.length : 0,
                // Which dead end the reader hit, so the empty screens can be counted and ranked
                // against each other instead of only showing up as a clip count of zero.
                ...(items.length === 0 ? { empty_reason: values.emptyReason ?? 'unresolved' } : {}),
            })
        },
    })),

    selectors({
        /** Null until both probes answer, so an empty screen is never drawn from unresolved data. */
        emptyReason: [
            (s) => [s.scanners, s.scannersLoading, s.quota, s.quotaLoading, s.onlyMyScanners],
            (
                scanners: ReplayScannerApi[],
                scannersLoading: boolean,
                quota: VisionQuotaApi | null,
                quotaLoading: boolean,
                onlyMyScanners: boolean
            ): WatchFeedEmptyReason | null =>
                scannersLoading || quotaLoading
                    ? null
                    : // The feed does not say anything about recording being off; that card lives in the picks column.
                      resolveWatchFeedEmptyReason({
                          scanners,
                          quota,
                          sessionRecordingOptIn: null,
                          hasFeedFilters: onlyMyScanners,
                      }),
        ],
    }),

    // The tab content mounts only while the tab is active, so mount is the fetch signal.
    afterMount(({ actions, cache }) => {
        cache.impressions = new WatchFeedImpressions('feed_tab', (load, ids) =>
            recordFeedImpressions(load.feedLoadId, ids)
        )
        // Not paused on hide: hiding is when the batch must go out.
        cache.disposables.add(cache.impressions.flushOnHideAndUnmount, 'impressionsFlush', { pauseOnPageHidden: false })
        actions.loadFeed()
    }),
])
