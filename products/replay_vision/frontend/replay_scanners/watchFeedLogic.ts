import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import posthog from 'lib/posthog-typed'
import { sessionPlayerModalLogic } from 'scenes/session-recordings/player/modal/sessionPlayerModalLogic'
import { teamLogic } from 'scenes/teamLogic'

import { visionScannersWatchFeedRetrieve } from '../generated/api'
import type { VisionScannersWatchFeedRetrieveParams, WatchFeedItemApi } from '../generated/api.schemas'
import type { ScannerTypeEnumApi } from '../generated/api.schemas'
import { ScannerType } from './types'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface watchFeedLogicValues {
    dateFrom: string
    dateTo: string | null
    feedFailed: boolean
    feedItems: WatchFeedItemApi[] | null
    feedItemsLoading: boolean
    scannerTypeFilter: ScannerType | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface watchFeedLogicActions {
    loadFeed: () => {
        value: true
    }
    loadFeedFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFeedSuccess: (
        feedItems: WatchFeedItemApi[],
        payload?: {
            value: true
        }
    ) => {
        feedItems: WatchFeedItemApi[]
        payload?: {
            value: true
        }
    }
    setDateRange: (
        dateFrom: string | null,
        dateTo: string | null
    ) => {
        dateFrom: string | null
        dateTo: string | null
    }
    setScannerTypeFilter: (scannerType: ScannerType | null) => {
        scannerType: ScannerTypeEnumApi | null
    }
}

export type watchFeedLogicType = MakeLogicType<watchFeedLogicValues, watchFeedLogicActions>

export const DEFAULT_FEED_DATE_FROM: string = '-7d'

/** Data for the What to watch tab: the window's most watchable observations, ranked server-side. */
export const watchFeedLogic = kea<watchFeedLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'watchFeedLogic']),

    actions({
        setDateRange: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setScannerTypeFilter: (scannerType: ScannerType | null) => ({ scannerType }),
        loadFeed: true,
    }),

    loaders(({ values }) => ({
        feedItems: [
            null as WatchFeedItemApi[] | null,
            {
                loadFeed: async (_, breakpoint) => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        // Reporting this as a successful empty result would read as "nothing to watch";
                        // fail instead so the tab shows the error state and a retry.
                        throw new Error('No current team')
                    }
                    const params: VisionScannersWatchFeedRetrieveParams = { date_from: values.dateFrom }
                    if (values.dateTo) {
                        params.date_to = values.dateTo
                    }
                    if (values.scannerTypeFilter) {
                        params.scanner_type = values.scannerTypeFilter
                    }
                    const response = await visionScannersWatchFeedRetrieve(String(teamId), params)
                    // Drop out-of-order responses — the most recent filter change owns the feed.
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),

    reducers({
        dateFrom: [
            DEFAULT_FEED_DATE_FROM,
            {
                setDateRange: (_, { dateFrom }) => dateFrom ?? DEFAULT_FEED_DATE_FROM,
            },
        ],
        dateTo: [
            null as string | null,
            {
                setDateRange: (_, { dateTo }) => dateTo,
            },
        ],
        scannerTypeFilter: [
            null as ScannerType | null,
            {
                setScannerTypeFilter: (_, { scannerType }) => scannerType,
            },
        ],
        feedFailed: [
            false,
            {
                loadFeed: () => false,
                loadFeedFailure: () => true,
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        setDateRange: () => {
            posthog.capture('replay_vision_watch_feed_filtered', {
                date_from: values.dateFrom,
                date_to: values.dateTo,
                scanner_type: values.scannerTypeFilter,
            })
            actions.loadFeed()
        },
        setScannerTypeFilter: () => {
            posthog.capture('replay_vision_watch_feed_filtered', {
                date_from: values.dateFrom,
                date_to: values.dateTo,
                scanner_type: values.scannerTypeFilter,
            })
            actions.loadFeed()
        },
        loadFeedSuccess: ({ feedItems }) => {
            posthog.capture('replay_vision_watch_feed_viewed', {
                clip_count: feedItems?.length ?? 0,
                scanner_count: new Set((feedItems ?? []).map((item) => item.observation.scanner_id)).size,
            })
        },
        // A card writes `?t=<seconds>` so the player opens at the cited moment; clear it on close so a
        // link copied afterwards doesn't seek a recording the user is no longer looking at.
        [sessionPlayerModalLogic.actionTypes.closeSessionPlayer]: () => {
            const { location, searchParams, hashParams } = router.values
            if (searchParams.t === undefined) {
                return
            }
            const nextParams = { ...searchParams }
            delete nextParams.t
            router.actions.replace(location.pathname, nextParams, hashParams)
        },
    })),

    // The tab content mounts only while the tab is active, so mount is the fetch signal.
    afterMount(({ actions }) => {
        actions.loadFeed()
    }),
])
