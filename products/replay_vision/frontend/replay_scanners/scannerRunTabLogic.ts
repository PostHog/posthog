/** Backs the on-demand recordings list: per-session observation lookup, scan bridging, and result polling. */
export const scannerRunTabLogic = kea<scannerRunTabLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'scannerRunTabLogic']),
    props({} as ScannerRunTabLogicProps),
    key((props) => props.scannerId),

    connect((props: ScannerRunTabLogicProps) => ({
        values: [replayScannerLogic({ id: props.scannerId }), ['triggeringOnDemandObservation']],
        actions: [
            replayScannerLogic({ id: props.scannerId }),
            ['triggerOnDemandObservation', 'triggerOnDemandObservationSuccess', 'triggerOnDemandObservationFailure'],
        ],
    })),

    actions({
        setVisibleSessionIds: (sessionIds: string[]) => ({ sessionIds }),
        startScan: (sessionId: string) => ({ sessionId }),
        startBulkScan: (sessionIds: string[]) => ({ sessionIds }),
        bulkScanDone: (started: number) => ({ started }),
        setPendingId: (sessionId: string) => ({ sessionId }),
        loadObservations: (background = false) => ({ background }),
        loadObservationsSuccess: (bySession: Record<string, RowObservation>) => ({ bySession }),
        loadObservationsFailure: true,
    }),

    reducers({
        visibleSessionIds: [
            [] as string[],
            {
                setVisibleSessionIds: (_, { sessionIds }) => sessionIds,
            },
        ],
        observationBySession: [
            {} as Record<string, RowObservation>,
            {
                // Merge over the previous map so rows scrolled out of the fetch keep their last-known state.
                loadObservationsSuccess: (state, { bySession }) => ({ ...state, ...bySession }),
            },
        ],
        // Bridges click-to-row gap: kept until the observation lands or the trigger fails, so the spinner holds.
        pendingId: [
            null as string | null,
            {
                setPendingId: (_, { sessionId }) => sessionId,
                triggerOnDemandObservationFailure: () => null,
                loadObservationsSuccess: (state, { bySession }) => (state && bySession[state] ? null : state),
            },
        ],
        // Drives the table's loading bar on foreground refetches only; background polls reload silently.
        refreshingObservations: [
            false,
            {
                loadObservations: (state, { background }) => (background ? state : true),
                loadObservationsSuccess: () => false,
                loadObservationsFailure: () => false,
            },
        ],
        // Loading state for the "Scan N selected" bulk button.
        bulkScanning: [
            false,
            {
                startBulkScan: () => true,
                bulkScanDone: () => false,
            },
        ],
        // A bulk trigger only starts the workflows; each row is inserted moments later. Nothing else
        // holds the poll open for them — unlike a single scan, which keeps `pendingId` until its row lands.
        pollUntil: [
            0,
            {
                bulkScanDone: (state: number, { started }: { started: number }) =>
                    started > 0 ? Date.now() + OBSERVE_POLL_GRACE_MS : state,
            },
        ],
    }),

    selectors({
        shouldPoll: [
            (s) => [s.visibleSessionIds, s.observationBySession, s.pendingId],
            (
                visibleSessionIds: string[],
                observationBySession: Record<string, RowObservation>,
                pendingId: string | null
            ): boolean =>
                pendingId !== null ||
                visibleSessionIds.some((id) => {
                    const observation = observationBySession[id]
                    return !!observation && IN_PROGRESS_STATUSES.has(observation.status)
                }),
        ],
    }),

    listeners(({ actions, props, values, cache }) => {
        // Rescheduled on failure too — a transient API hiccup shouldn't permanently kill the polling cycle.
        const reschedulePoll = (): void =>
            scheduleObservationPoll(
                cache.disposables,
                shouldPollObservations(values.shouldPoll, values.pollUntil),
                () => actions.loadObservations(true)
            )
        return {
            setVisibleSessionIds: ({ sessionIds }) => {
                if (sessionIds.length > 0) {
                    actions.loadObservations()
                }
            },

            startScan: ({ sessionId }) => {
                if (values.triggeringOnDemandObservation || values.pendingId) {
                    return
                }
                actions.setPendingId(sessionId)
                actions.triggerOnDemandObservation(sessionId, true)
            },

            startBulkScan: async ({ sessionIds }) => {
                const teamId = teamLogic.values.currentTeamId
                if (!teamId || sessionIds.length === 0) {
                    actions.bulkScanDone(0)
                    return
                }
                // The backend scans what fits and reports the rest — surface the split so the user
                // knows a partial run happened rather than assuming everything started.
                const skipCounts: BulkSkipCounts = {
                    skipped_limit: 0,
                    skipped_quota: 0,
                    skipped_scanner_limit: 0,
                }
                let started = 0
                let failed = 0
                let alreadyScanned = 0
                let alreadyRunning = 0
                try {
                    for (let sent = 0; sent < sessionIds.length; sent += MAX_SESSIONS_PER_REQUEST) {
                        const batch = sessionIds.slice(sent, sent + MAX_SESSIONS_PER_REQUEST)
                        const response = await visionScannersBulkObserveCreate(String(teamId), props.scannerId, {
                            session_ids: batch,
                        })
                        started += response.started
                        let batchSkipped = 0
                        for (const r of response.results ?? []) {
                            if (r.scan_outcome && r.scan_outcome in skipCounts) {
                                skipCounts[r.scan_outcome as BulkSkipOutcome] += 1
                                batchSkipped += 1
                            } else if (r.scan_outcome === 'failed') {
                                failed += 1
                            } else if (r.scan_outcome === 'already_scanned') {
                                alreadyScanned += 1
                            } else if (r.scan_outcome === 'already_running') {
                                alreadyRunning += 1
                            }
                        }
                        if (batchSkipped > 0) {
                            // A cap bound on this batch, so every later one would be skipped for the same
                            // reason. Count the rest of the selection under it instead of asking again.
                            skipCounts[dominantSkip(skipCounts)] += sessionIds.length - sent - batch.length
                            break
                        }
                    }
                    const limited =
                        skipCounts.skipped_limit + skipCounts.skipped_quota + skipCounts.skipped_scanner_limit
                    const extras = [
                        limited ? `${limited} skipped (${BULK_SKIP_REASONS[dominantSkip(skipCounts)]})` : null,
                        alreadyScanned ? `${alreadyScanned} already scanned` : null,
                        alreadyRunning ? `${alreadyRunning} already scanning` : null,
                        failed ? `${failed} failed to start` : null,
                    ]
                        .filter(Boolean)
                        .join(', ')
                    if (started > 0) {
                        lemonToast.success(
                            `Started ${started} scan${started === 1 ? '' : 's'}${extras ? ` — ${extras}` : ''}`
                        )
                    } else if (limited > 0) {
                        lemonToast.warning(BULK_SKIP_MESSAGES[dominantSkip(skipCounts)])
                    } else if (alreadyScanned + alreadyRunning > 0 && failed === 0) {
                        // Every session already has an answer or one on the way, so retrying is the one
                        // thing that would not help.
                        lemonToast.info('Nothing new to scan. These recordings are already scanned or in progress.')
                    } else {
                        lemonToast.error('No scans started. Please try again.')
                    }
                } catch (error: any) {
                    // The backend only reports a bulk trigger once it has accepted the batch, so without
                    // this a rejected selection leaves no trace in analytics at all.
                    posthog.capture('replay_vision_bulk_scan_rejected', {
                        scanner_id: props.scannerId,
                        requested: sessionIds.length,
                        started,
                        status: error?.status,
                    })
                    // A later batch can fail after an earlier one started scans, so say how many survived.
                    const detail = error?.detail ? `: ${error.detail}` : ''
                    lemonToast.error(
                        started > 0
                            ? `Bulk scan failed after starting ${started} scan${started === 1 ? '' : 's'}${detail}`
                            : `Bulk scan failed${detail}`
                    )
                } finally {
                    // Arm the poll window before the refetch, which can beat the row inserts.
                    actions.bulkScanDone(started)
                    // Started scans create pending observations server-side — refetch to reflect them.
                    // Also on failure: an earlier batch can have started scans before a later one failed.
                    actions.loadObservations()
                }
            },

            // A successful trigger creates a pending observation server-side — refetch to pick it up.
            triggerOnDemandObservationSuccess: () => actions.loadObservations(),

            loadObservations: async (_, breakpoint) => {
                const teamId = teamLogic.values.currentTeamId
                const sessionIds = values.visibleSessionIds
                if (!teamId || sessionIds.length === 0) {
                    actions.loadObservationsFailure() // Clear the foreground loading flag; a bare return spins forever.
                    return
                }
                try {
                    // Ordering pinned: the newest-wins mapping below depends on it, not on the API default.
                    // Without a limit the server's default page truncates the tail and those sessions read
                    // as "Not scanned" when they have been.
                    const response = await visionScannersObservationsList(String(teamId), props.scannerId, {
                        session_id: sessionIds.join(','),
                        order_by: '-created_at',
                        limit: sessionIds.length * OBSERVATIONS_PER_SESSION_ALLOWANCE,
                    })
                    breakpoint()
                    const bySession: Record<string, RowObservation> = {}
                    for (const observation of response.results ?? []) {
                        // Results are newest-first — the first observation per session is the one the row reflects.
                        if (!(observation.session_id in bySession)) {
                            bySession[observation.session_id] = {
                                id: observation.id,
                                status: observation.status,
                                errorReason: observation.error_reason || null,
                            }
                        }
                    }
                    actions.loadObservationsSuccess(bySession)
                } catch (error) {
                    if (error instanceof Error && isBreakpoint(error)) {
                        throw error
                    }
                    // Best-effort enrichment — on failure the rows just stay scannable, but keep polling alive.
                    actions.loadObservationsFailure()
                }
            },

            loadObservationsSuccess: reschedulePoll,
            loadObservationsFailure: reschedulePoll,
        }
    }),
])
