export const scannerAlertNotificationLogic = kea<scannerAlertNotificationLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'scannerAlertNotificationLogic']),
    props({} as ScannerAlertNotificationLogicProps),
    key(({ alertId }) => alertId ?? 'new'),

    connect({
        values: [teamLogic, ['currentTeamId'], integrationsLogic, ['integrationsLoading', 'slackIntegrations']],
        actions: [integrationsLogic, ['loadIntegrations', 'loadIntegrationsFailure', 'loadIntegrationsSuccess']],
    }),

    actions({
        addPendingNotification: (notification: PendingVisionAlertNotification) => ({ notification }),
        addSelectedNotification: true,
        removePendingNotification: (index: number) => ({ index }),
        clearPendingNotifications: true,
        setPendingNotifications: (notifications: PendingVisionAlertNotification[]) => ({ notifications }),
        deleteExistingDestination: (group: VisionAlertDestinationGroup) => ({ group }),
        createPendingHogFunctions: (alertId: string) => ({ alertId }),
        setSelectedType: (selectedType: VisionAlertNotificationType) => ({ selectedType }),
        setSelectedSlackIntegrationId: (selectedSlackIntegrationId: number | null) => ({
            selectedSlackIntegrationId,
        }),
        setSlackChannelValue: (slackChannelValue: string | null) => ({ slackChannelValue }),
        setWebhookUrl: (webhookUrl: string) => ({ webhookUrl }),
    }),

    reducers({
        pendingNotifications: [
            [] as PendingVisionAlertNotification[],
            {
                addPendingNotification: (state, { notification }) => [...state, notification],
                removePendingNotification: (state, { index }) => state.filter((_, i) => i !== index),
                clearPendingNotifications: () => [],
                setPendingNotifications: (_, { notifications }) => notifications,
            },
        ],
        integrationsFailed: [
            false,
            {
                loadIntegrations: () => false,
                loadIntegrationsFailure: () => true,
                loadIntegrationsSuccess: () => false,
            },
        ],
        slackChannelValue: [
            null as string | null,
            {
                setSlackChannelValue: (_, { slackChannelValue }) => slackChannelValue,
                setSelectedSlackIntegrationId: () => null,
            },
        ],
        selectedSlackIntegrationId: [
            null as number | null,
            {
                setSelectedSlackIntegrationId: (_, { selectedSlackIntegrationId }) => selectedSlackIntegrationId,
            },
        ],
        webhookUrl: [
            '' as string,
            {
                setWebhookUrl: (_, { webhookUrl }) => webhookUrl,
            },
        ],
        selectedType: [
            VISION_ALERT_NOTIFICATION_TYPE_SLACK as VisionAlertNotificationType,
            {
                setSelectedType: (_, { selectedType }) => selectedType,
            },
        ],
    }),

    loaders(({ props }) => ({
        existingHogFunctions: [
            [] as HogFunctionType[],
            {
                loadExistingHogFunctions: async (alertId?: string) => {
                    const id = alertId ?? props.alertId
                    if (!id) {
                        return []
                    }
                    const response = await api.hogFunctions.list({
                        types: ['internal_destination'],
                        filter_groups: [buildVisionAlertFilterConfig(id)],
                        full: true,
                    })
                    return response.results
                },
            },
        ],
    })),

    selectors({
        selectedSlackIntegration: [
            (s) => [s.slackIntegrations, s.selectedSlackIntegrationId],
            (
                slackIntegrations: IntegrationType[] | undefined,
                selectedSlackIntegrationId: number | null
            ): IntegrationType | undefined =>
                slackIntegrations?.find((integration) => integration.id === selectedSlackIntegrationId) ??
                slackIntegrations?.[0],
        ],
        urlInput: [
            (s) => [s.selectedType],
            (selectedType: VisionAlertNotificationType): AlertNotificationUrlInput | undefined =>
                selectedType === VISION_ALERT_NOTIFICATION_TYPE_WEBHOOK
                    ? { placeholder: 'https://example.com/webhook' }
                    : undefined,
        ],
        addDisabledReason: [
            (s) => [s.selectedType, s.selectedSlackIntegration, s.slackChannelValue, s.webhookUrl],
            (
                selectedType: VisionAlertNotificationType,
                selectedSlackIntegration: IntegrationType | undefined,
                slackChannelValue: string | null,
                webhookUrl: string
            ): string | undefined => {
                if (selectedType !== VISION_ALERT_NOTIFICATION_TYPE_SLACK) {
                    return webhookUrl ? undefined : 'Enter a webhook URL'
                }
                if (!selectedSlackIntegration) {
                    return 'Connect Slack first'
                }
                return slackChannelValue ? undefined : 'Select a Slack channel'
            },
        ],
        destinationGroups: [
            (s) => [s.existingHogFunctions],
            (hogFunctions: HogFunctionType[]): VisionAlertDestinationGroup[] =>
                groupVisionAlertDestinations(hogFunctions),
        ],
    }),

    listeners(({ actions, values, props }) => ({
        addSelectedNotification: () => {
            if (values.selectedType === VISION_ALERT_NOTIFICATION_TYPE_SLACK) {
                if (!values.slackChannelValue || !values.selectedSlackIntegration) {
                    return
                }
                const [channelId, channelLabel] = values.slackChannelValue.split('|')
                actions.addPendingNotification({
                    type: VISION_ALERT_NOTIFICATION_TYPE_SLACK,
                    slackWorkspaceId: values.selectedSlackIntegration.id,
                    slackChannelId: channelId,
                    slackChannelName: channelLabel?.replace('#', '') ?? channelId,
                })
                actions.setSlackChannelValue(null)
                return
            }
            if (!values.webhookUrl) {
                return
            }
            actions.addPendingNotification({
                type: VISION_ALERT_NOTIFICATION_TYPE_WEBHOOK,
                webhookUrl: values.webhookUrl,
            })
            actions.setWebhookUrl('')
        },
        addPendingNotification: () => {
            if (props.alertId) {
                actions.createPendingHogFunctions(props.alertId)
            }
        },
        loadIntegrationsSuccess: ({ integrations }) => {
            const availableSlackIntegrations = integrations.filter((integration) => integration.kind === 'slack')
            if (
                !availableSlackIntegrations.some((integration) => integration.id === values.selectedSlackIntegrationId)
            ) {
                actions.setSelectedSlackIntegrationId(availableSlackIntegrations[0]?.id ?? null)
            }
            if (availableSlackIntegrations.length === 0) {
                actions.setSelectedType(VISION_ALERT_NOTIFICATION_TYPE_WEBHOOK)
            }
        },
        deleteExistingDestination: async ({ group }) => {
            if (!props.alertId) {
                return
            }
            try {
                await visionAlertsDestinationsDeleteCreate(String(values.currentTeamId), props.alertId, {
                    hog_function_ids: group.hogFunctions.map((hf) => hf.id),
                })
                lemonToast.success(`Removed ${group.label}`)
            } catch {
                lemonToast.error(`Could not remove ${group.label}. Try again.`)
            }
            actions.loadExistingHogFunctions()
        },
        createPendingHogFunctions: async ({ alertId }) => {
            const pending = values.pendingNotifications
            if (pending.length === 0) {
                return
            }

            const projectId = String(values.currentTeamId)
            const results = await Promise.allSettled(
                pending.map((notification) => {
                    const payload =
                        notification.type === VISION_ALERT_NOTIFICATION_TYPE_SLACK
                            ? {
                                  type: VISION_ALERT_NOTIFICATION_TYPE_SLACK,
                                  slack_workspace_id: notification.slackWorkspaceId,
                                  slack_channel_id: notification.slackChannelId,
                                  slack_channel_name: notification.slackChannelName,
                              }
                            : {
                                  type: notification.type,
                                  webhook_url: notification.webhookUrl,
                              }
                    return visionAlertsDestinationsCreate(projectId, alertId, payload)
                })
            )

            const failedNotifications = pending.filter((_, i) => results[i].status === 'rejected')
            actions.loadExistingHogFunctions(alertId)

            if (failedNotifications.length > 0) {
                lemonToast.error(
                    `Alert saved, but ${failedNotifications.length} notification destination(s) could not be created. Reopen the alert to add them again.`
                )
                actions.setPendingNotifications(failedNotifications)
            } else {
                lemonToast.success(`${pending.length} notification destination(s) created.`)
                actions.clearPendingNotifications()
            }
        },
    })),

    afterMount(({ actions, props }) => {
        if (props.alertId) {
            actions.loadExistingHogFunctions()
        }
    }),
])
