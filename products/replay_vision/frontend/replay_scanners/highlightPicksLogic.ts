export const highlightPicksLogic: LogicWrapper<highlightPicksLogicType> = kea<highlightPicksLogicType>([
    props({} as HighlightPicksLogicProps),
    key((props) => props.logicKey),
    path((key) => ['products', 'replay_vision', 'frontend', 'replay_scanners', 'highlightPicksLogic', key]),

    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    actions({
        loadPicks: true,
        setListMode: (mode: HighlightPicksListMode) => ({ mode }),
        adoptPicksMode: true,
        highlightPick: (item: HighlightFeedItemApi, position: number) => ({ item, position }),
        setActiveSessionId: (sessionId: string | null) => ({ sessionId }),
        markPickViewed: (observationId: string) => ({ observationId }),
        setPicksLoad: (load: HighlightFeedLoad) => ({ load }),
        cardSeen: (item: HighlightFeedItemApi, position: number) => ({ item, position }),
        emptyStateShown: (reason: HighlightFeedEmptyReason) => ({ reason }),
        emptyStateAction: (reason: HighlightFeedEmptyReason, action: string) => ({ reason, action }),
        docsOpened: true,
    }),

    loaders(({ values, actions }) => ({
        picks: [
            null as HighlightFeedItemApi[] | null,
            {
                loadPicks: async (_, breakpoint) => {
                    if (!values.currentTeamId) {
                        throw new Error('No current team')
                    }
                    const response = await visionScannersHighlightFeedRetrieve(String(values.currentTeamId), {
                        date_from: PICKS_DATE_FROM,
                        limit: PICKS_LIMIT,
                    })
                    breakpoint()
                    actions.setPicksLoad(newHighlightFeedLoad(response.results))
                    return response.results
                },
            },
        ],
    })),

    reducers(() => ({
        picks: {
            markPickViewed: (state, { observationId }) =>
                state?.map((pick) =>
                    pick.observation.id === observationId
                        ? { ...pick, observation: { ...pick.observation, viewed: true } }
                        : pick
                ) ?? null,
        },
        picksLoad: [
            null as HighlightFeedLoad | null,
            {
                setPicksLoad: (_, { load }) => load,
            },
        ],
        listMode: [
            null as HighlightPicksListMode | null,
            { persist: true, storageKey: 'replay-vision.highlight-picks-list-mode' },
            {
                setListMode: (_, { mode }) => mode,
                adoptPicksMode: () => 'picks',
            },
        ],
        emptyImpressionsAtMount: [emptyImpressions.get() ?? 0, {}],
        openedOnDeepLink: [replayUrlPointsSomewhere(router.values.searchParams, router.values.hashParams), {}],
        picksFailed: [
            false,
            {
                loadPicks: () => false,
                loadPicksFailure: () => true,
            },
        ],
        activeSessionId: [
            null as string | null,
            {
                setActiveSessionId: (_, { sessionId }) => sessionId,
            },
        ],
    })),

    selectors({
        effectiveListMode: [
            (s) => [s.listMode, s.openedOnDeepLink, s.picksFailed, s.emptyImpressionsAtMount],
            (
                listMode: HighlightPicksListMode | null,
                openedOnDeepLink: boolean,
                picksFailed: boolean,
                emptyImpressionsAtMount: number
            ): HighlightPicksListMode =>
                listMode ??
                (openedOnDeepLink || picksFailed || emptyImpressionsAtMount >= EMPTY_IMPRESSIONS_BEFORE_RECORDINGS
                    ? 'recordings'
                    : 'picks'),
        ],
        unwatchedCount: [
            (s) => [s.picks],
            (picks: HighlightFeedItemApi[] | null): number =>
                (picks ?? []).filter((pick) => !pick.observation.viewed).length,
        ],
    }),

    listeners(({ actions, props, values, cache }) => {
        const reportPicksShown = (): void => {
            if (!values.picks || values.effectiveListMode !== 'picks') {
                return
            }
            if (values.picks.length === 0) {
                if (values.listMode === null && !cache.emptyImpressionNoted) {
                    cache.emptyImpressionNoted = true
                    emptyImpressions.set((emptyImpressions.get() ?? 0) + 1)
                }
                return
            }
            const shownCount = (picksShownCount.get() ?? 0) + 1
            picksShownCount.set(shownCount)
            posthog.capture('replay_vision_highlight_picks_shown', {
                ...servedListProperties(values.picksLoad, values.picks),
                view: 'list',
                count: values.picks.length,
                unwatched_count: values.unwatchedCount,
                shown_count: shownCount,
            })
            if (shownCount === PICKS_SHOWN_SURVEY_IMPRESSION) {
                posthog.capture('replay_vision_highlight_picks_shown_third_time', { view: 'list' })
            }
        }
        return {
            loadPicksSuccess: () => {
                cache.picksLoadedAt = Date.now()
                reportPicksShown()
            },
            adoptPicksMode: () => {
                emptyImpressions.set(0)
            },
            setPicksLoad: ({ load }) => {
                cache.impressions.start(load)
            },
            emptyStateShown: ({ reason }) => {
                if (cache.emptyStateShownReason === reason) {
                    return
                }
                cache.emptyStateShownReason = reason
                posthog.capture('replay_vision_highlight_picks_empty_shown', { reason })
            },
            emptyStateAction: ({ reason, action }) => {
                posthog.capture('replay_vision_highlight_picks_empty_action', { reason, action })
            },
            docsOpened: () => {
                posthog.capture('replay_vision_highlight_picks_docs_opened')
            },
            cardSeen: ({ item, position }) => {
                // Fallback rows below the picks were not served by the ranker, so they are not impressions of this load.
                if (values.picksLoad?.positions[item.observation.id] !== undefined) {
                    cache.impressions.add(item, position)
                }
            },
            setListMode: ({ mode }) => {
                posthog.capture('replay_vision_highlight_picks_list_mode_changed', { mode })
                if (mode === 'picks') {
                    reportPicksShown()
                }
            },
            highlightPick: async ({ item, position }) => {
                const { observation } = item
                const keyMomentMs = observationKeyMomentMs(observation)
                posthog.capture('replay_vision_highlight_clip_clicked', {
                    ...cardProperties(
                        values.picksLoad?.positions[observation.id] !== undefined ? values.picksLoad : null,
                        item,
                        position,
                        'list'
                    ),
                    scanner_type: observation.scanner_snapshot?.scanner_type,
                    has_key_moment: keyMomentMs !== null,
                    target: 'replay_page',
                    view: 'list',
                })
                const playerParams = {
                    t: keyMomentMs === null ? undefined : highlightStartSeconds(keyMomentMs),
                    sidebarTab: SessionRecordingSidebarTab.OBSERVATIONS,
                    showInspector: true,
                }
                const markViewed =
                    !observation.viewed && values.currentTeamId
                        ? visionObservationsViewedCreate(String(values.currentTeamId), observation.id)
                        : null
                sessionReplaySceneLogic.findMounted()?.actions.setPickSeekSessionId(observation.session_id)
                const { location, searchParams, hashParams } = router.values
                router.actions.replace(location.pathname, { ...searchParams, ...playerParams }, hashParams)
                sessionRecordingsPlaylistLogic(props.playlistLogicProps).actions.setSelectedRecordingId(
                    observation.session_id
                )
                playerSettingsLogic.findMounted()?.actions.openWatchPanelSection('observations')
                if (!markViewed) {
                    return
                }
                const mountedIn = getContext()
                try {
                    await markViewed
                } catch {
                    return
                }
                if (getContext() === mountedIn && !cache.disposables.isDisposed) {
                    actions.markPickViewed(observation.id)
                }
            },
            [sessionRecordingsPlaylistLogic(props.playlistLogicProps).actionTypes.setSelectedRecordingId]: ({
                id,
            }: {
                id: string | null
            }) => {
                actions.setActiveSessionId(id)
            },
        }
    }),

    afterMount(({ actions, cache }) => {
        cache.impressions = new HighlightFeedImpressions('list', (load, ids) =>
            recordFeedImpressions(load.feedLoadId, ids)
        )
        // Not paused on hide: hiding is when the batch must go out.
        cache.disposables.add(cache.impressions.flushOnHideAndUnmount, 'impressionsFlush', { pauseOnPageHidden: false })
        actions.loadPicks()
        cache.disposables.add(() => {
            const onFocus = (): void => {
                if (Date.now() - (cache.picksLoadedAt ?? 0) >= FOCUS_RELOAD_MIN_MS) {
                    actions.loadPicks()
                }
            }
            window.addEventListener('focus', onFocus)
            return () => window.removeEventListener('focus', onFocus)
        }, 'focus-reload')
    }),
])
