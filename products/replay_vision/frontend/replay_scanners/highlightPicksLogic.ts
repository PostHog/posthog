const PICKS_LIMIT = 50
const PICKS_DATE_FROM = '-7d'

// Survey display conditions can only trigger on an event name, so the third
// impression of the picks in the list is reported as its own event. The
// impression count lives in this browser only
export const PICKS_SHOWN_SURVEY_IMPRESSION = 3
const teamStorageKey = (key: string) => (): string =>
    `${key}.${teamLogic.findMounted()?.values.currentTeamId ?? 'unknown'}`
export const picksShownCountStorageKey = teamStorageKey('replay-vision.highlight-picks-shown-count')
const picksShownCount = localStorageSlot(picksShownCountStorageKey, z.number().int().nonnegative())
export const emptyImpressionsStorageKey = teamStorageKey('replay-vision.highlight-picks-empty-impressions')
export const EMPTY_IMPRESSIONS_BEFORE_RECORDINGS = 2
const emptyImpressions = localStorageSlot(emptyImpressionsStorageKey, z.number().int().nonnegative())
const FOCUS_RELOAD_MIN_MS = 60_000

