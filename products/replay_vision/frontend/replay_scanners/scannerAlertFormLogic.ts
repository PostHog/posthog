export type VisionAlertKind = 'metric' | 'match'

export interface ScannerAlertFormType {
    name: string
    kind: VisionAlertKind
    verdict: string[]
    tags: string[]
    minScore: number | null
    maxScore: number | null
    metric: 'count' | 'avg_score'
    direction: 'above' | 'below'
    threshold: number | null
    windowDays: number
    evaluationPeriods: number
    datapointsToAlarm: number
    cooldownMinutes: number
    scheduleRestriction: ScheduleRestriction | null
}

export interface ScannerAlertFormLogicProps {
    scannerId: string
    alert: VisionAlertConfigurationApi | null
    onSubmitSuccess?: () => void
}

export function buildFormDefaults(alert: VisionAlertConfigurationApi | null): ScannerAlertFormType {
    const selection = (alert?.selection ?? {}) as Record<string, unknown>
    return {
        name: alert?.name ?? '',
        kind: (alert?.kind as VisionAlertKind) ?? 'match',
        verdict: (selection.verdict as string[] | undefined) ?? [],
        tags: (selection.tags as string[] | undefined) ?? [],
        minScore: (selection.min_score as number | undefined) ?? null,
        maxScore: (selection.max_score as number | undefined) ?? null,
        metric: alert?.metric ?? 'count',
        direction: alert?.direction ?? 'above',
        threshold: alert?.threshold ?? null,
        windowDays: alert?.window_days ?? 1,
        evaluationPeriods: alert?.evaluation_periods ?? 1,
        datapointsToAlarm: alert?.datapoints_to_alarm ?? 1,
        cooldownMinutes: alert?.cooldown_minutes ?? 0,
        scheduleRestriction: (alert?.schedule_restriction as ScheduleRestriction | null) ?? null,
    }
}

export function buildSelection(form: ScannerAlertFormType): Record<string, unknown> {
    const selection: Record<string, unknown> = {}
    if (form.verdict.length) {
        selection.verdict = form.verdict
    }
    if (form.tags.length) {
        selection.tags = form.tags
    }
    if (form.minScore !== null) {
        selection.min_score = form.minScore
    }
    if (form.maxScore !== null) {
        selection.max_score = form.maxScore
    }
    return selection
}

function saveErrorMessage(error: ApiError): string {
    return error.detail ?? error.message ?? 'Could not save the alert. Try again.'
}

