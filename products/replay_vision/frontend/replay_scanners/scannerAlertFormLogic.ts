export const scannerAlertFormLogic = kea<scannerAlertFormLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'scannerAlertFormLogic']),
    props({} as ScannerAlertFormLogicProps),
    key(({ alert, scannerId }) => alert?.id ?? `new-${scannerId}`),

    connect(({ alert, scannerId }: ScannerAlertFormLogicProps) => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            scannerAlertNotificationLogic({ alertId: alert?.id }),
            ['pendingNotifications'],
        ],
        actions: [
            scannerAlertsLogic({ scannerId }),
            ['loadAlerts', 'updateEditingAlert'],
            scannerAlertNotificationLogic({ alertId: alert?.id }),
            ['createPendingHogFunctions'],
        ],
    })),

    selectors({
        isEditing: [() => [(_, props) => props.alert], (alert: VisionAlertConfigurationApi | null) => alert !== null],
    }),

    afterMount(({ actions, props }) => {
        // Pass values explicitly to reset — kea caches logic instances by key, so defaults
        // from a previous mount may be stale.
        actions.resetAlertForm(buildFormDefaults(props.alert))
    }),

    forms(({ props, actions, values }) => ({
        alertForm: {
            defaults: buildFormDefaults(props.alert),
            errors: ({ name, kind, threshold }) => ({
                name: !name?.trim() ? 'Enter an alert name.' : undefined,
                threshold: kind === 'metric' && threshold === null ? 'Enter a threshold.' : undefined,
            }),
            submit: async (form) => {
                if (form.scheduleRestriction?.blocked_windows) {
                    const quietHoursIssue = findQuietHoursIssues(form.scheduleRestriction.blocked_windows)
                    if (quietHoursIssue) {
                        throw new Error(quietHoursIssue.message)
                    }
                }

                const projectId = String(values.currentTeamId)
                const isMetric = form.kind === 'metric'
                const payload = {
                    scanner_id: props.scannerId,
                    name: form.name.trim(),
                    kind: form.kind,
                    selection: buildSelection(form),
                    // The drain holds match bundles through quiet hours too.
                    schedule_restriction: form.scheduleRestriction,
                    ...(isMetric
                        ? {
                              metric: form.metric,
                              direction: form.direction,
                              threshold: form.threshold,
                              window_days: form.windowDays,
                              evaluation_periods: form.evaluationPeriods,
                              datapoints_to_alarm: form.datapointsToAlarm,
                              cooldown_minutes: form.cooldownMinutes,
                          }
                        : {}),
                }

                let savedAlertId: string
                try {
                    if (props.alert) {
                        // kind and scanner are immutable server-side; leave them out of the patch.
                        const { kind: _kind, scanner_id: _scanner, ...patch } = payload
                        const updated = await visionAlertsPartialUpdate(projectId, props.alert.id, patch)
                        actions.updateEditingAlert(updated)
                        savedAlertId = props.alert.id
                        lemonToast.success('Alert updated')
                    } else {
                        const created = await visionAlertsCreate(projectId, payload as any)
                        savedAlertId = created.id
                        lemonToast.success('Alert created')
                    }
                } catch (error: unknown) {
                    lemonToast.error(saveErrorMessage(error as ApiError))
                    throw error
                }

                try {
                    if (values.pendingNotifications.length > 0) {
                        const notifLogic = scannerAlertNotificationLogic({ alertId: props.alert?.id })
                        await notifLogic.asyncActions.createPendingHogFunctions(savedAlertId)
                    }
                } catch {
                    lemonToast.error('Alert saved, but notifications could not be configured.')
                }

                actions.loadAlerts()
                props.onSubmitSuccess?.()
                return form
            },
        },
    })),
])
