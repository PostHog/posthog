import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { subscriptions } from 'kea-subscriptions'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { teamLogic } from 'scenes/teamLogic'

import { visionScannersObservationsStatsRetrieve } from '../generated/api'

export type CalibrationActivationVariant = 'control' | 'badge' | 'prompt'

export interface CalibrationActivationLogicProps {
    scannerId: string
}

export interface CalibrationStats {
    ratedTotal: number
    succeededTotal: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface calibrationActivationLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    neverRated: boolean
    requested: boolean
    stats: CalibrationStats | null
    variant: CalibrationActivationVariant
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface calibrationActivationLogicActions {
    loadStats: () => {
        value: true
    }
    loadStatsSuccess: (
        ratedTotal: number,
        succeededTotal: number
    ) => {
        ratedTotal: number
        succeededTotal: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface calibrationActivationLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        variant: (featureFlags: FeatureFlagsSet) => CalibrationActivationVariant
        neverRated: (stats: CalibrationStats | null) => boolean
    }
}

export type calibrationActivationLogicType = MakeLogicType<
    calibrationActivationLogicValues,
    calibrationActivationLogicActions,
    CalibrationActivationLogicProps,
    calibrationActivationLogicMeta
>

/** Only the arms that render something fetch the rating count, so the control arm costs no request. */
export const calibrationActivationLogic = kea<calibrationActivationLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'calibrationActivationLogic']),
    props({} as CalibrationActivationLogicProps),
    key((props) => props.scannerId),

    connect(() => ({ values: [featureFlagLogic, ['featureFlags']] })),

    actions({
        loadStats: true,
        loadStatsSuccess: (ratedTotal: number, succeededTotal: number) => ({ ratedTotal, succeededTotal }),
    }),

    reducers({
        // Set when the action dispatches, not when the response lands, so a variant that changes again
        // while the request is in flight cannot start a second one.
        requested: [false, { loadStats: () => true }],
        // Null until the counts are known, so a nudge cannot flash on a scanner that is rated already.
        stats: [
            null as CalibrationStats | null,
            {
                loadStatsSuccess: (_, { ratedTotal, succeededTotal }) => ({ ratedTotal, succeededTotal }),
            },
        ],
    }),

    selectors({
        variant: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): CalibrationActivationVariant => {
                const value = featureFlags[FEATURE_FLAGS.REPLAY_VISION_CALIBRATION_ACTIVATION]
                return value === 'badge' || value === 'prompt' ? value : 'control'
            },
        ],
        // Both counts come from one all-time response, so they cannot disagree about the window. Only a
        // succeeded observation can be rated, which makes it the ratable total.
        neverRated: [
            (s) => [s.stats],
            (stats: CalibrationStats | null): boolean =>
                stats !== null && stats.succeededTotal > 0 && stats.ratedTotal === 0,
        ],
    }),

    listeners(({ actions, props }) => ({
        loadStats: async (_, breakpoint) => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                return
            }
            try {
                // recent_days is only for the daily series; the totals it also returns are all-time.
                const response = await visionScannersObservationsStatsRetrieve(String(teamId), props.scannerId, {
                    recent_days: 1,
                })
                breakpoint()
                actions.loadStatsSuccess(
                    response.labels.up_total + response.labels.down_total,
                    response.status_counts.succeeded
                )
            } catch {
                // A failed count leaves `stats` null, so the nudge stays hidden. Nothing to report.
            }
        },
    })),

    // `subscriptions` must stay below `listeners`. It fires once at mount with the flag already in
    // hand, and a dispatch made before the listener attaches is lost, which would leave the count
    // unfetched. This ordering is what makes a single mount fetch exactly once.
    subscriptions(({ actions, values }) => ({
        variant: (variant: CalibrationActivationVariant) => {
            if (variant !== 'control' && !values.requested) {
                actions.loadStats()
            }
        },
    })),
])
