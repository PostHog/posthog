const DROUGHT_SCANNER_CAP = 10
const BACKFILL_DAYS = 7
const NEXT_BEST_COUNT = 5
const WINDOW_DATE_FROM = '-7d'
const BACKFILL_POLL_MS = 10_000
const BACKFILL_POLL_MAX = 60

export interface BackfillEstimate {
    scannerId: string
    sessions: number
    credits: number
}

function backfillWindow(): { window_start: string; window_end: string } {
    return {
        window_start: dayjs().subtract(BACKFILL_DAYS, 'day').toISOString(),
        window_end: dayjs().toISOString(),
    }
}

