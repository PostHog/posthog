export const highlightPicksStaleLogic: LogicWrapper<highlightPicksStaleLogicType> = kea<highlightPicksStaleLogicType>([
    props({} as HighlightPicksStaleLogicProps),
    key((props) => props.logicKey),
    path((key) => ['products', 'replay_vision', 'frontend', 'replay_scanners', 'highlightPicksStaleLogic', key]),

    connect((props: HighlightPicksStaleLogicProps) => ({
        values: [
            teamLogic,
            ['currentTeamId', 'currentTeam'],
            visionScannersListLogic,
            ['scanners'],
            visionQuotaLogic,
            ['quota'],
            highlightPicksLogic(props),
            ['picks'],
        ],
        actions: [visionScannersListLogic, ['loadScannersSuccess'], highlightPicksLogic(props), ['loadPicksSuccess']],
    })),

    actions({
        loadDroughtScannerIds: true,
        loadQuietWeek: true,
        loadNextBest: true,
        toggleScanner: (scannerId: string, enabled: boolean) => ({ scannerId, enabled }),
        raiseLimit: (scannerId: string, creditLimit: number) => ({ scannerId, creditLimit }),
        startBackfill: (scannerId: string) => ({ scannerId }),
        backfillStarted: (scannerId: string, totalSessions: number) => ({ scannerId, totalSessions }),
        scannerActionDone: (scannerId: string) => ({ scannerId }),
        pickBackfillScanner: (scannerId: string | null) => ({ scannerId }),
        loadBackfillEstimate: true,
        pickSharperGoal: (goalKey: string) => ({ goalKey }),
    }),

    loaders(({ values }) => ({
        droughtScannerIds: [
            [] as string[],
            {
                loadDroughtScannerIds: async (_, breakpoint) => {
                    const teamId = values.currentTeamId
                    if (!teamId) {
                        return []
                    }
                    const now = new Date()
                    const candidates = values.scanners
                        .filter((scanner) => scanner.enabled && !scanner.limit_reached)
                        .slice(0, DROUGHT_SCANNER_CAP)
                    const results = await Promise.all(
                        candidates.map(async (scanner) => {
                            try {
                                const stats = await visionScannersObservationsStatsRetrieve(String(teamId), scanner.id)
                                return scanDrought(
                                    {
                                        ...scanner,
                                        enabled: scanner.enabled ?? false,
                                        sampling_rate: scanner.sampling_rate ?? 1,
                                    },
                                    stats.labels.version_markers,
                                    now
                                )
                                    ? scanner.id
                                    : null
                            } catch {
                                return null
                            }
                        })
                    )
                    breakpoint()
                    return results.filter((id): id is string => id !== null)
                },
            },
        ],
        quietWeek: [
            null as QuietWeekStats | null,
            {
                loadQuietWeek: async (_, breakpoint) => {
                    const teamId = values.currentTeamId
                    if (!teamId) {
                        return null
                    }
                    const stats = await Promise.all(
                        values.scanners.slice(0, DROUGHT_SCANNER_CAP).map((scanner) =>
                            visionScannersObservationsStatsRetrieve(String(teamId), scanner.id, {
                                date_from: WINDOW_DATE_FROM,
                            }).catch(() => null)
                        )
                    )
                    breakpoint()
                    return stats.reduce<QuietWeekStats>(
                        (acc, stat) => ({
                            scanned: acc.scanned + (stat?.status_counts.total ?? 0),
                            succeeded: acc.succeeded + (stat?.status_counts.succeeded ?? 0),
                        }),
                        { scanned: 0, succeeded: 0 }
                    )
                },
            },
        ],
        backfillEstimate: [
            null as BackfillEstimate | null,
            {
                loadBackfillEstimate: async (_, breakpoint) => {
                    const teamId = values.currentTeamId
                    const scannerId = values.backfillScannerId
                    if (!teamId || !scannerId) {
                        return null
                    }
                    await breakpoint(100)
                    const estimate = await visionScannersBackfillsEstimateCreate(
                        String(teamId),
                        scannerId,
                        backfillWindow()
                    )
                    breakpoint()
                    return { scannerId, sessions: estimate.total_sessions, credits: estimate.total_credits }
                },
            },
        ],
        nextBest: [
            null as ReplayObservationApi[] | null,
            {
                loadNextBest: async (_, breakpoint) => {
                    const teamId = values.currentTeamId
                    if (!teamId) {
                        return null
                    }
                    const pages = await Promise.all(
                        values.scanners.slice(0, DROUGHT_SCANNER_CAP).map((scanner) =>
                            visionScannersObservationsList(String(teamId), scanner.id, {
                                date_from: WINDOW_DATE_FROM,
                                status: 'succeeded',
                                order_by: '-created_at',
                                limit: NEXT_BEST_COUNT,
                            }).catch(() => null)
                        )
                    )
                    breakpoint()
                    return pages
                        .flatMap((page) => page?.results ?? [])
                        .sort((a, b) => b.created_at.localeCompare(a.created_at))
                        .slice(0, NEXT_BEST_COUNT)
                },
            },
        ],
    })),

    reducers({
        pickedBackfillScannerId: [
            null as string | null,
            {
                pickBackfillScanner: (_, { scannerId }) => scannerId,
            },
        ],
        now: [
            new Date(),
            {
                loadPicksSuccess: () => new Date(),
            },
        ],
        busyScannerId: [
            null as string | null,
            {
                toggleScanner: (_, { scannerId }) => scannerId,
                raiseLimit: (_, { scannerId }) => scannerId,
                startBackfill: (_, { scannerId }) => scannerId,
                scannerActionDone: () => null,
            },
        ],
        backfillTotals: [
            {} as Record<string, number>,
            {
                backfillStarted: (state, { scannerId, totalSessions }) => ({ ...state, [scannerId]: totalSessions }),
            },
        ],
    }),

    selectors({
        blockReason: [
            (s) => [s.scanners, s.quota, s.currentTeam],
            (
                scanners: ReplayScannerApi[],
                quota: VisionQuotaApi | null,
                currentTeam: TeamPublicType | TeamType | null
            ): HighlightFeedEmptyReason =>
                resolveHighlightFeedEmptyReason({
                    scanners,
                    quota,
                    sessionRecordingOptIn: currentTeam?.session_recording_opt_in ?? null,
                    hasFeedFilters: false,
                }),
        ],
        staleReason: [
            (s) => [s.picks, s.blockReason, s.droughtScannerIds, s.now],
            (
                picks: HighlightFeedItemApi[] | null,
                blockReason: HighlightFeedEmptyReason,
                droughtScannerIds: string[],
                now: Date
            ): HighlightPicksStaleReason | null =>
                resolveHighlightPicksStaleReason({ picks: picks ?? [], blockReason, droughtScannerIds, now }),
        ],
        backfillCandidates: [
            (s) => [s.scanners],
            (scanners: ReplayScannerApi[]): ReplayScannerApi[] =>
                scanners.filter((scanner) => scanner.enabled && !scanner.limit_reached),
        ],
        backfillScannerId: [
            (s) => [s.pickedBackfillScannerId, s.backfillCandidates],
            (picked: string | null, candidates: ReplayScannerApi[]): string | null =>
                candidates.some((scanner) => scanner.id === picked) ? picked : (candidates[0]?.id ?? null),
        ],
        lastSweptAt: [
            (s) => [s.backfillCandidates],
            (candidates: ReplayScannerApi[]): string | null =>
                candidates.reduce<string | null>(
                    (latest, scanner) => (!latest || scanner.last_swept_at > latest ? scanner.last_swept_at : latest),
                    null
                ),
        ],
        droughtScanners: [
            (s) => [s.scanners, s.droughtScannerIds],
            (scanners: ReplayScannerApi[], droughtScannerIds: string[]): ReplayScannerApi[] =>
                scanners.filter((scanner) => droughtScannerIds.includes(scanner.id)),
        ],
    }),

    listeners(({ actions, values, props, cache }) => {
        const refresh = (): void => {
            visionScannersListLogic.findMounted()?.actions.loadScanners()
            visionQuotaLogic.findMounted()?.actions.loadQuota()
            highlightPicksLogic.findMounted(props)?.actions.loadPicks()
        }
        const act = (action: string, scannerId: string | null, extra: Record<string, string> = {}): void => {
            posthog.capture('replay_vision_highlight_picks_stale_action', {
                // With no picks there is no stale reason, so the empty reason names the state that held the button.
                reason: values.staleReason ?? values.blockReason,
                action,
                scanner_id: scannerId,
                ...extra,
            })
        }
        return {
            pickSharperGoal: ({ goalKey }) => {
                const running = values.scanners.filter((scanner) => scanner.enabled && !scanner.limit_reached)
                act('sharper_goal', running.length === 1 ? running[0].id : null, { goal_key: goalKey })
            },
            loadScannersSuccess: () => {
                if (values.picks && values.picks.length > 0) {
                    cache.droughtsLoaded = true
                    actions.loadDroughtScannerIds()
                }
            },
            loadPicksSuccess: ({ picks }) => {
                if (picks.length === 0 || values.scanners.length === 0) {
                    return
                }
                if (!cache.droughtsLoaded) {
                    cache.droughtsLoaded = true
                    actions.loadDroughtScannerIds()
                } else if (values.staleReason === 'quiet-week' && values.quietWeek === null) {
                    actions.loadQuietWeek()
                }
            },
            loadDroughtScannerIdsSuccess: () => {
                if (values.staleReason === 'quiet-week' && values.quietWeek === null) {
                    actions.loadQuietWeek()
                }
                if (values.staleReason) {
                    posthog.capture('replay_vision_highlight_picks_stale_shown', { reason: values.staleReason })
                }
            },
            toggleScanner: async ({ scannerId, enabled }) => {
                const teamId = values.currentTeamId
                if (!teamId) {
                    return
                }
                act(enabled ? 'enable' : 'disable', scannerId)
                try {
                    await visionScannersPartialUpdate(String(teamId), scannerId, { enabled })
                    refresh()
                } finally {
                    actions.scannerActionDone(scannerId)
                }
            },
            raiseLimit: async ({ scannerId, creditLimit }) => {
                const teamId = values.currentTeamId
                if (!teamId) {
                    return
                }
                act('raise_limit', scannerId)
                try {
                    await visionScannersPartialUpdate(String(teamId), scannerId, {
                        credit_limit: creditLimit,
                        free_only: false,
                    })
                    refresh()
                } finally {
                    actions.scannerActionDone(scannerId)
                }
            },
            backfillStarted: ({ totalSessions }) => {
                if (totalSessions === 0) {
                    return
                }
                let polls = 0
                cache.disposables.add(() => {
                    const timer = window.setInterval(() => {
                        polls += 1
                        const picks = highlightPicksLogic.findMounted(props)?.values.picks ?? []
                        if (polls > BACKFILL_POLL_MAX || picks.length > 0) {
                            cache.disposables.dispose('backfill-poll')
                            return
                        }
                        highlightPicksLogic.findMounted(props)?.actions.loadPicks()
                    }, BACKFILL_POLL_MS)
                    return () => clearInterval(timer)
                }, 'backfill-poll')
            },
            startBackfill: async ({ scannerId }) => {
                const teamId = values.currentTeamId
                if (!teamId) {
                    return
                }
                act('backfill', scannerId)
                const window = backfillWindow()
                try {
                    const estimate = await visionScannersBackfillsEstimateCreate(String(teamId), scannerId, window)
                    if (estimate.total_sessions > 0) {
                        await visionScannersBackfillsCreate(String(teamId), scannerId, {
                            ...window,
                            max_total_credits: estimate.total_credits,
                        })
                    }
                    actions.backfillStarted(scannerId, estimate.total_sessions)
                } catch {
                    actions.backfillStarted(scannerId, 0)
                } finally {
                    actions.scannerActionDone(scannerId)
                }
            },
        }
    }),

    subscriptions(({ actions }) => ({
        backfillScannerId: (scannerId: string | null) => {
            if (scannerId) {
                actions.loadBackfillEstimate()
            }
        },
    })),
])
