export const replayFiltersScannerLogic = kea<replayFiltersScannerLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'replayFiltersScannerLogic']),
    connect(() => ({ values: [visionQuotaLogic, ['freeCreditsLeft']] })),

    actions({
        setPopoverOpen: (open: boolean) => ({ open }),
        setGoal: (goal: string) => ({ goal }),
        setCreditCap: (cap: ReplayFiltersCreditCap) => ({ cap }),
        setBudget: (budget: number | null) => ({ budget }),
        draftWithAi: (handoff: ScannerHandoffFromFilters, spend?: GoalDraftSpend) => ({ handoff, spend }),
        setUpManually: (handoff: ScannerHandoffFromFilters) => ({ handoff }),
        requestConsent: (spend: GoalDraftSpend) => ({ spend }),
        confirmConsent: (handoff: ScannerHandoffFromFilters, spend: GoalDraftSpend) => ({ handoff, spend }),
        cancelConsent: true,
    }),

    reducers({
        popoverOpen: [
            false,
            {
                setPopoverOpen: (_, { open }) => open,
                draftWithAi: () => false,
                setUpManually: () => false,
            },
        ],
        goal: [
            '',
            {
                setGoal: (_, { goal }) => goal,
            },
        ],
        // The spend chosen when consent was asked for, so a quota that loads meanwhile cannot change it.
        consentSpend: [
            null as GoalDraftSpend | null,
            {
                requestConsent: (_, { spend }) => spend,
                cancelConsent: () => null,
                setPopoverOpen: () => null,
                draftWithAi: () => null,
            },
        ],
        creditCap: [
            'free' as ReplayFiltersCreditCap,
            {
                setCreditCap: (_, { cap }) => cap,
            },
        ],
        budget: [
            DEFAULT_GOAL_BUDGET as number | null,
            {
                // A cleared number input emits NaN, which would otherwise serialize to null in the hand-off.
                setBudget: (_, { budget }) => (budget != null && Number.isFinite(budget) ? budget : null),
            },
        ],
    }),

    selectors({
        spendChoice: [
            (s) => [s.creditCap, s.budget, s.freeCreditsLeft],
            (
                creditCap: ReplayFiltersCreditCap,
                budget: number | null,
                freeCreditsLeft: number | null
            ): GoalSpendChoice => goalSpendChoice(creditCap === 'free' ? 'free' : 'budget', budget, freeCreditsLeft),
        ],
        draftInputDisabledReason: [
            (s) => [s.goal, s.spendChoice, s.budget],
            (goal: string, spendChoice: GoalSpendChoice, budget: number | null): string | null => {
                if (!goal.trim()) {
                    return 'Say what the scanner should watch for or answer'
                }
                const capInRange = budget != null && Number.isInteger(budget) && budget >= 1 && budget <= MAX_CREDIT_CAP
                if (!spendChoice.spend || (spendChoice.mode === 'budget' && !capInRange)) {
                    return 'Enter a monthly credit cap from 1 to 100,000,000 credits'
                }
                return null
            },
        ],
    }),

    listeners(({ values, actions }) => ({
        setPopoverOpen: ({ open }) => {
            if (open) {
                reportClicked('open')
            }
        },
        // Approving consent can trigger a full-page SSO reauthentication, which unloads the page before
        // the draft starts. So the draft is stored once the person confirms, for as long as the consent
        // flow waits to resume. Not earlier: a click in the consent dialog closes both popovers.
        confirmConsent: ({ handoff, spend }) => {
            const goal = values.goal.trim()
            if (goal) {
                markScannerGoalDraftIntent(
                    { goal, query: handoff.chosenQuery, spend, source: REPLAY_FILTERS_ENTRY_POINT },
                    { ttlMs: AI_CONSENT_PENDING_REDIRECT_TTL_MS }
                )
            }
        },
        draftWithAi: ({ handoff, spend: capturedSpend }) => {
            const goal = values.goal.trim()
            const spend = capturedSpend ?? values.spendChoice.spend
            if (!goal || !spend) {
                return
            }
            reportClicked('draft_with_ai', handoff.narrowsSessions)
            recordCrossSellIntent()
            const armed = markScannerGoalDraftIntent({
                goal,
                query: handoff.chosenQuery,
                spend,
                source: REPLAY_FILTERS_ENTRY_POINT,
            })
            if (!armed) {
                // Without storage the wizard cannot receive the filters, so open it with them in the URL instead.
                router.actions.push(manualWizardUrl(handoff))
                return
            }
            actions.setGoal('')
            router.actions.push(urls.replayVisionNewScanner())
        },
        setUpManually: ({ handoff }) => {
            reportClicked('set_up_manually', handoff.narrowsSessions)
            recordCrossSellIntent()
            router.actions.push(manualWizardUrl(handoff))
        },
    })),
])
