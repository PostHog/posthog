import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { combineUrl, router } from 'kea-router'
import posthog from 'posthog-js'

import { addProductIntentForCrossSell } from 'lib/utils/product-intents'
import { AI_CONSENT_PENDING_REDIRECT_TTL_MS } from 'scenes/settings/organization/aiConsentLogic'
import { urls } from 'scenes/urls'

import { ProductIntentContext, ProductKey } from '~/queries/schema/schema-general'

import { visionQuotaLogic } from '../logics/visionQuotaLogic'
import { DEFAULT_GOAL_BUDGET, type GoalDraftSpend, type GoalSpendChoice, goalSpendChoice } from './replayScannerLogic'
import type { ScannerHandoffFromFilters } from './scannerHandoffFromFilters'
import { markScannerGoalDraftIntent } from './scannerHandoffIntent'

export type ReplayFiltersCreditCap = 'free' | 'cap'

// The draft API's limit for `monthly_credit_budget`.
const MAX_CREDIT_CAP = 100_000_000

// Pinned: the `placement` on the shared replay_vision_upsell_* events and the scanner's `entry_point`.
export const REPLAY_FILTERS_ENTRY_POINT = 'replay_filters'

function reportClicked(cta: 'open' | 'draft_with_ai' | 'set_up_manually', narrowsSessions?: boolean): void {
    posthog.capture('replay_vision_upsell_clicked', {
        placement: REPLAY_FILTERS_ENTRY_POINT,
        cta,
        narrows_sessions: narrowsSessions ?? null,
    })
}

function manualWizardUrl(handoff: ScannerHandoffFromFilters): string {
    return combineUrl(urls.replayVisionScannerConfigure('new'), {
        ...handoff.searchParams,
        entry_point: REPLAY_FILTERS_ENTRY_POINT,
    }).url
}

function recordCrossSellIntent(): void {
    void addProductIntentForCrossSell({
        from: ProductKey.SESSION_REPLAY,
        to: ProductKey.REPLAY_VISION,
        intent_context: ProductIntentContext.SESSION_REPLAY_SAVE_FILTERS_AS_SCANNER,
    })
}

