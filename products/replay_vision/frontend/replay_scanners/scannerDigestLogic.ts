export const scannerDigestLogic = kea<scannerDigestLogicType>([
    path(['products', 'replay_vision', 'frontend', 'replay_scanners', 'scannerDigestLogic']),
    props({} as ScannerDigestLogicProps),
    key((props) => props.scannerId),

    connect((props: ScannerDigestLogicProps) => ({
        values: [visionActionsLogic({ scannerId: props.scannerId }), ['visionActions', 'visionActionsLoading']],
        actions: [
            visionActionsLogic({ scannerId: props.scannerId }),
            ['loadActions', 'loadActionsSuccess', 'toggleActionEnabled', 'addAction'],
        ],
    })),

    actions({
        loadLatestRun: true,
        loadLatestRunSuccess: (run: VisionActionRunApi | null) => ({ run }),
        loadLatestRunFailure: true,
        createDigest: true,
        createDigestSuccess: true,
        createDigestFailure: true,
        promoteDigest: (actionId: string) => ({ actionId }),
        promoteDigestSuccess: true,
        promoteDigestFailure: true,
        runNow: true,
        runNowDone: true,
        openPeriodModal: true,
        closePeriodModal: true,
        setPeriodRange: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setCoverageTier: (tier: CoverageTierKey) => ({ tier }),
        loadRunPreview: true,
        loadRunPreviewSuccess: (preview: RunPreviewResponseApi) => ({ preview }),
        loadRunPreviewFailure: true,
        summarizePeriod: true,
        summarizePeriodDone: true,
        setRunInProgress: (inProgress: boolean) => ({ inProgress }),
        toggleExpanded: true,
    }),

    reducers({
        // The digest's newest completed run; kept while a refresh is in flight so the card doesn't flash.
        latestRun: [
            null as VisionActionRunApi | null,
            {
                loadLatestRunSuccess: (_, { run }) => run,
            },
        ],
        latestRunLoading: [
            true,
            {
                loadLatestRun: () => true,
                loadLatestRunSuccess: () => false,
                loadLatestRunFailure: () => false,
            },
        ],
        digestCreating: [
            false,
            {
                createDigest: () => true,
                createDigestSuccess: () => false,
                createDigestFailure: () => false,
            },
        ],
        // In-flight promotion of an existing summary into the featured slot; disables the dropdown.
        promoting: [
            false,
            {
                promoteDigest: () => true,
                promoteDigestSuccess: () => false,
                promoteDigestFailure: () => false,
            },
        ],
        expanded: [
            false,
            {
                toggleExpanded: (state) => !state,
            },
        ],
        // Loading state for the digest card's "Run now" button (the ~1s trigger request).
        runningNow: [
            false,
            {
                runNow: () => true,
                runNowDone: () => false,
            },
        ],
        // A digest run is actively processing (from the runs list) — disables "Run now" and drives polling.
        runInProgress: [
            false,
            {
                setRunInProgress: (_, { inProgress }) => inProgress,
            },
        ],
        periodModalOpen: [
            false,
            {
                openPeriodModal: () => true,
                closePeriodModal: () => false,
            },
        ],
        // The DateFilter tokens picked in the period modal; resolved to ISO instants only on submit.
        periodDateFrom: [
            DEFAULT_PERIOD_DATE_FROM as string | null,
            {
                setPeriodRange: (_, { dateFrom }) => dateFrom,
            },
        ],
        periodDateTo: [
            null as string | null,
            {
                setPeriodRange: (_, { dateTo }) => dateTo,
            },
        ],
        // The coverage tier picked in the period modal; back to the cheapest default on every open so
        // an expensive choice never carries over silently.
        coverageTier: [
            'standard' as CoverageTierKey,
            {
                setCoverageTier: (_, { tier }) => tier,
                openPeriodModal: () => 'standard' as CoverageTierKey,
            },
        ],
        // The modal's pre-run count/cost preview for the picked range. Cleared on a range change so a
        // stale count is never shown against the new range.
        runPreview: [
            null as RunPreviewResponseApi | null,
            {
                loadRunPreviewSuccess: (_, { preview }) => preview,
                setPeriodRange: () => null,
                openPeriodModal: () => null,
            },
        ],
        runPreviewLoading: [
            false,
            {
                loadRunPreview: () => true,
                loadRunPreviewSuccess: () => false,
                loadRunPreviewFailure: () => false,
            },
        ],
        // Loading state for the period modal's submit button (the ~1s trigger request).
        summarizingPeriod: [
            false,
            {
                summarizePeriod: () => true,
                summarizePeriodDone: () => false,
            },
        ],
        // Keep polling for a grace window after a manual run: the workflow creates its run row
        // asynchronously, so the RUNNING row usually isn't there on the refresh right after triggering.
        pollUntil: [
            0,
            {
                runNow: () => Date.now() + OBSERVE_POLL_GRACE_MS,
                summarizePeriod: () => Date.now() + OBSERVE_POLL_GRACE_MS,
            },
        ],
    }),

    selectors({
        digest: [
            (s) => [s.visionActions],
            (visionActions: VisionActionApi[]): VisionActionApi | null =>
                visionActions.find((a) => a.is_scanner_digest) ?? null,
        ],
        // Summaries eligible to be promoted into the featured slot: scheduled group summaries that
        // aren't already the digest (alerts don't produce a summary the card can render).
        promotableSummaries: [
            (s) => [s.visionActions],
            (visionActions: VisionActionApi[]): VisionActionApi[] =>
                visionActions.filter((a) => a.mode === 'group_summary' && !a.is_scanner_digest),
        ],
        shouldPoll: [
            (s) => [s.runInProgress, s.pollUntil],
            (runInProgress: boolean, pollUntil: number): boolean => shouldPollObservations(runInProgress, pollUntil),
        ],
        // The observation cap the picked tier submits with the run. Preview tiers carry the
        // server-defined caps; before the preview loads, fall back to the mirrored constants.
        selectedTierCap: [
            (s) => [s.runPreview, s.coverageTier],
            (runPreview: RunPreviewResponseApi | null, coverageTier: CoverageTierKey): number =>
                runPreview?.tiers.find((t) => t.key === coverageTier)?.max_observations ??
                FALLBACK_TIER_CAPS[coverageTier],
        ],
    }),

    listeners(({ actions, props, values, cache }) => {
        // Reschedule after every settle so polling stops once no run is in flight and the grace window
        // has elapsed. Rescheduled on failure too, so a transient hiccup can't kill the cycle.
        const reschedulePoll = (): void =>
            scheduleObservationPoll(cache.disposables, values.shouldPoll, () => actions.loadLatestRun())
        return {
            loadActionsSuccess: () => {
                if (values.digest) {
                    actions.loadLatestRun()
                } else {
                    // No digest → nothing to fetch; clear the initial loading state so the opt-in card shows.
                    actions.loadLatestRunSuccess(null)
                }
            },

            loadLatestRun: async (_, breakpoint) => {
                const teamId = teamLogic.values.currentTeamId
                const digest = values.digest
                if (!teamId || !digest) {
                    actions.loadLatestRunFailure()
                    return
                }
                try {
                    const page = await visionActionsRunsList(String(teamId), digest.id, { limit: RUN_LOOKBACK })
                    breakpoint()
                    const results = page.results ?? []
                    // Surface an in-flight run so the card can show "Running…" and disable Run now.
                    actions.setRunInProgress(results.some((r) => r.status === VisionActionRunStatusEnumApi.Running))
                    const completed = results.find((r) => r.status === VisionActionRunStatusEnumApi.Completed)
                    if (!completed) {
                        actions.loadLatestRunSuccess(null)
                        return
                    }
                    // The run list is deliberately light (no report body); fetch the full run for the markdown.
                    const run = await visionActionsRunsRetrieve(String(teamId), digest.id, completed.id)
                    breakpoint()
                    actions.loadLatestRunSuccess(run)
                } catch {
                    // Silent: the card falls back to the "first digest is on its way" state.
                    actions.loadLatestRunFailure()
                }
            },

            createDigest: async () => {
                const teamId = teamLogic.values.currentTeamId
                if (!teamId) {
                    actions.createDigestFailure()
                    return
                }
                try {
                    const created = await visionActionsCreate(String(teamId), {
                        // Mirrors the backend provisioning defaults (digest.py) for scanners created before
                        // digests existed, or after the digest was deleted.
                        name: `Daily digest: ${props.scannerName}`.slice(0, 255),
                        scanner: props.scannerId,
                        is_scanner_digest: true,
                        trigger_config: {
                            rrule: SCANNER_DIGEST_RRULE,
                            timezone: teamLogic.values.currentTeam?.timezone || 'UTC',
                        },
                        delivery_config: [],
                    })
                    actions.createDigestSuccess()
                    lemonToast.success('Daily digest turned on')
                    // Insert the created digest optimistically instead of refetching the list — a refetch
                    // would blank the card (visionActionsLoading true, digest still absent) and flash it.
                    actions.addAction(created)
                    // A brand-new digest has no runs yet, so resolve the run state locally rather than
                    // fetching; this keeps the card from flashing through its latestRunLoading gap.
                    actions.loadLatestRunSuccess(null)
                } catch (error: any) {
                    actions.createDigestFailure()
                    lemonToast.error(`Couldn't turn on the daily digest${error?.detail ? `: ${error.detail}` : ''}`)
                }
            },

            promoteDigest: async ({ actionId }) => {
                const teamId = teamLogic.values.currentTeamId
                if (!teamId) {
                    actions.promoteDigestFailure()
                    return
                }
                try {
                    // Server atomically demotes the scanner's current digest (if any) before flagging this one.
                    await visionActionsPartialUpdate(String(teamId), actionId, { is_scanner_digest: true })
                    actions.promoteDigestSuccess()
                    lemonToast.success('Featured digest updated')
                    // Refetch rather than patch locally: promotion also demotes the previous digest row.
                    actions.loadActions()
                } catch (error: any) {
                    actions.promoteDigestFailure()
                    lemonToast.error(`Couldn't update the featured digest${error?.detail ? `: ${error.detail}` : ''}`)
                }
            },

            runNow: async () => {
                const teamId = teamLogic.values.currentTeamId
                const digest = values.digest
                if (!teamId || !digest) {
                    actions.runNowDone()
                    return
                }
                try {
                    const { already_running } = await visionActionsRunCreate(String(teamId), digest.id)
                    lemonToast.success(
                        already_running
                            ? 'A digest is already being generated — it will appear here shortly.'
                            : "Generating the digest now. It'll appear here in a minute or two."
                    )
                    // Refresh + poll so the card picks up the running run and then the finished summary.
                    actions.loadLatestRun()
                } catch (error: any) {
                    lemonToast.error(`Couldn't run the digest${error?.detail ? `: ${error.detail}` : ''}`)
                } finally {
                    actions.runNowDone()
                }
            },

            openPeriodModal: () => actions.loadRunPreview(),
            setPeriodRange: () => actions.loadRunPreview(),

            loadRunPreview: async (_, breakpoint) => {
                // Debounced: the user may still be stepping through ranges in the picker.
                await breakpoint(PREVIEW_DEBOUNCE_MS)
                const teamId = teamLogic.values.currentTeamId
                const digest = values.digest
                if (!teamId || !digest) {
                    actions.loadRunPreviewFailure()
                    return
                }
                try {
                    const preview = await visionActionsRunPreviewRetrieve(String(teamId), digest.id, {
                        window_start: resolveWindowBound(values.periodDateFrom, dayjs().subtract(30, 'day')),
                        window_end: resolveWindowBound(values.periodDateTo, dayjs()),
                    })
                    breakpoint()
                    actions.loadRunPreviewSuccess(preview)
                } catch (error: any) {
                    if (isBreakpoint(error)) {
                        // A newer preview superseded this one; its own settle drives the loading state.
                        throw error
                    }
                    // Silent: the modal falls back to its static coverage copy and still allows generating.
                    actions.loadRunPreviewFailure()
                }
            },

            summarizePeriod: async () => {
                const teamId = teamLogic.values.currentTeamId
                const digest = values.digest
                if (!teamId || !digest) {
                    actions.summarizePeriodDone()
                    return
                }
                const windowStart = resolveWindowBound(values.periodDateFrom, dayjs().subtract(30, 'day'))
                const windowEnd = resolveWindowBound(values.periodDateTo, dayjs())
                // The picker accepts future dates, but a period starting after its end (which defaults
                // to now) holds nothing to summarize; catch it here instead of surfacing a backend 400.
                if (!dayjs(windowStart).isBefore(windowEnd)) {
                    lemonToast.error('The period must start in the past. Pick an earlier start date.')
                    actions.summarizePeriodDone()
                    return
                }
                try {
                    const { already_running } = await visionActionsRunCreate(String(teamId), digest.id, {
                        window_start: windowStart,
                        window_end: windowEnd,
                        max_observations: values.selectedTierCap,
                    })
                    if (already_running) {
                        // The server coalesced onto the run already in flight, so the requested period
                        // did not start. Keep the modal open so the user can retry once it finishes.
                        lemonToast.info('A digest run is already in progress. Try again when it finishes.')
                    } else {
                        lemonToast.success("Generating the period summary now. It'll appear here in a minute or two.")
                        actions.closePeriodModal()
                    }
                    // Refresh + poll so the card picks up the running run and then the finished summary.
                    actions.loadLatestRun()
                } catch (error: any) {
                    lemonToast.error(`Couldn't start the period summary${error?.detail ? `: ${error.detail}` : ''}`)
                } finally {
                    actions.summarizePeriodDone()
                }
            },

            loadLatestRunSuccess: reschedulePoll,
            loadLatestRunFailure: reschedulePoll,
        }
    }),

    afterMount(({ actions, values }) => {
        // visionActionsLogic loads on its own mount; if it already settled (tab was visited first),
        // loadActionsSuccess won't fire again, so resolve the card state here.
        if (!values.visionActionsLoading) {
            if (values.digest) {
                actions.loadLatestRun()
            } else {
                actions.loadLatestRunSuccess(null)
            }
        }
    }),
])
