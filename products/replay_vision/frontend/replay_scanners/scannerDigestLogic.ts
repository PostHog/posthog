// Mirrors the backend default (digest.py); every morning at 8:00 in the team's timezone.
export const SCANNER_DIGEST_RRULE = 'FREQ=DAILY;BYHOUR=8;BYMINUTE=0'

// How many recent runs to scan for the newest completed one (skipped/failed runs don't carry a summary).
const RUN_LOOKBACK = 10

// Default period offered by the "Summarize a period" modal, and the fallback when a custom range
// leaves the start unset.
export const DEFAULT_PERIOD_DATE_FROM = '-30d'

export type CoverageTierKey = 'standard' | 'deep' | 'complete'

// Mirrors the backend tier caps (observation_window.py) for before the preview loads; once it has,
// the preview's tiers are the source of truth.
export const FALLBACK_TIER_CAPS: Record<CoverageTierKey, number> = { standard: 100, deep: 500, complete: 2000 }

// Debounce for the preview request while the user is still picking a range.
const PREVIEW_DEBOUNCE_MS = 300

