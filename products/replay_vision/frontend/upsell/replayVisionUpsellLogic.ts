/**
 * The Replay vision experiment for people who watch many recordings. The flag targets them, and
 * each test variant puts one card on the recordings page. Reading `variant` records the exposure,
 * so mount this logic only where a card can show.
 */
export const replayVisionUpsellLogic = kea<replayVisionUpsellLogicType>([
    path(['products', 'replay_vision', 'frontend', 'upsell', 'replayVisionUpsellLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            lemonBannerLogic({ dismissKey: REPLAY_VISION_UPSELL_DISMISS_KEY }),
            ['isDismissed'],
            teamLogic,
            ['currentTeamId'],
            visionQuotaLogic,
            ['freeCreditsAllowance'],
        ],
        actions: [lemonBannerLogic({ dismissKey: REPLAY_VISION_UPSELL_DISMISS_KEY }), ['dismiss as dismissBanner']],
    })),
    actions({
        dismiss: (placement: ReplayVisionUpsellPlacement) => ({ placement }),
        reportClicked: (placement: ReplayVisionUpsellPlacement, cta: ReplayVisionUpsellCta) => ({ placement, cta }),
    }),
    loaders(({ values }) => ({
        // The `load` prefix keeps a failed probe from showing an error toast. A failure leaves the
        // stats null, so the player card stays hidden.
        scannerStats: [
            null as ScannerStatsResponseApi | null,
            {
                loadScannerStats: async (_: void, breakpoint): Promise<ScannerStatsResponseApi | null> => {
                    if (!values.currentTeamId) {
                        return null
                    }
                    const response = await visionScannersStatsRetrieve(String(values.currentTeamId))
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    selectors({
        variant: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): ReplayVisionUpsellVariant | null => {
                const value = featureFlags[FEATURE_FLAGS.REPLAY_VISION_HEAVY_VIEWER_UPSELL]
                return UPSELL_VARIANTS.find((variant) => variant === value) ?? null
            },
        ],
        teamHasScanners: [
            (s) => [s.scannerStats],
            (scannerStats: ScannerStatsResponseApi | null): boolean | null =>
                scannerStats ? scannerStats.total > 0 : null,
        ],
        playerCard: [
            (s) => [s.variant, s.isDismissed, s.teamHasScanners],
            (
                variant: ReplayVisionUpsellVariant | null,
                isDismissed: boolean,
                teamHasScanners: boolean | null
            ): ReplayVisionPlayerCard | null => {
                if (variant !== 'player-card' || isDismissed || teamHasScanners === null) {
                    return null
                }
                return teamHasScanners ? 'team' : 'starter'
            },
        ],
        showListCard: [
            (s) => [s.variant, s.isDismissed],
            (variant: ReplayVisionUpsellVariant | null, isDismissed: boolean): boolean =>
                variant === 'list-card' && !isDismissed,
        ],
        // Both test variants stay without the launch banner after a dismissal, because the person
        // closed a Replay vision prompt and does not expect a different one in its place.
        replacesLaunchBanner: [
            (s) => [s.variant],
            (variant: ReplayVisionUpsellVariant | null): boolean =>
                variant === 'player-card' || variant === 'list-card',
        ],
    }),
    listeners(({ actions, values }) => ({
        dismiss: ({ placement }) => {
            // Pinned: the weekly cohort refresh removes people who send this event, so the card
            // also stops on their other browsers. localStorage only hides it in this browser.
            posthog.capture('replay_vision_upsell_dismissed', {
                placement,
                variant: values.variant,
                team_has_scanners: values.teamHasScanners,
            })
            actions.dismissBanner()
        },
        reportClicked: ({ placement, cta }) => {
            posthog.capture('replay_vision_upsell_clicked', {
                placement,
                cta,
                variant: values.variant,
                team_has_scanners: values.teamHasScanners,
            })
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.variant === 'player-card' && !values.isDismissed) {
            actions.loadScannerStats()
        }
    }),
])
