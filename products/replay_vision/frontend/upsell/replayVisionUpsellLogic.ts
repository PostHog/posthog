// Pinned: a localStorage key. Renaming it shows the upsell again to everyone who closed it.
export const REPLAY_VISION_UPSELL_DISMISS_KEY = 'replay-vision-heavy-viewer-upsell'

// Pinned: the flag's variant keys. The experiment reads these exact strings.
export type ReplayVisionUpsellVariant = 'control' | 'player-card' | 'list-card'
const UPSELL_VARIANTS: ReplayVisionUpsellVariant[] = ['control', 'player-card', 'list-card']

export type ReplayVisionUpsellPlacement = 'player' | 'list'
/** `team` is for a team that already has scanners, so the card points at them instead of a new one. */
export type ReplayVisionPlayerCard = 'starter' | 'team'
export type ReplayVisionUpsellCta = 'scan_filters' | 'set_up_scanner' | 'see_team_scanners'

export interface ReplayVisionUpsellTarget {
    url: string
    cta: Exclude<ReplayVisionUpsellCta, 'see_team_scanners'>
}

/**
 * A scanner made from filters that do not narrow the sessions would watch every session, so those
 * filters go to the empty new-scanner flow instead.
 */
export function upsellTargetForFilters(filters: RecordingUniversalFilters): ReplayVisionUpsellTarget {
    const handoff = scannerHandoffFromFilters(filters)
    if (!handoff.narrowsSessions) {
        return { url: urls.replayVisionNewScanner(), cta: 'set_up_scanner' }
    }
    return {
        url: combineUrl(urls.replayVisionScannerConfigure('new'), handoff.searchParams).url,
        cta: 'scan_filters',
    }
}

