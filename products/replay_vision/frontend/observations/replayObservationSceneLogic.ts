import { MakeLogicType, actions, beforeUnmount, kea, path, reducers, selectors } from 'kea'
import { urlToAction } from 'kea-router'

import { urls } from 'scenes/urls'

import { SIDE_PANEL_CONTEXT_KEY, SidePanelSceneContext } from '~/layout/navigation-3000/sidepanel/types'
import { ActivityScope, Breadcrumb } from '~/types'

import type {
    ReplayObservationApi,
    ObservationStatusEnumApi,
    VisionObservationsRetrieveParams,
} from '../generated/api.schemas'
import { VISION_ROOT_BREADCRUMB } from '../utils/breadcrumbs'

export type ObservationResultTab = 'summary' | 'timeline'

export interface ObservationsPage {
    rows: ReplayObservationApi[]
    number: number
    pageSize: number
    total: number
    filterParams: VisionObservationsRetrieveParams
}

/** The page the scanner table last loaded, so a row opened from it paints before its own read lands. */
export const lastObservationsPage: { current: ObservationsPage | null } = { current: null }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayObservationSceneLogicValues {
    breadcrumbs: Breadcrumb[]
    observationId: string
    observationStatus: ObservationStatusEnumApi | null
    parentBreadcrumb: Breadcrumb | null
    resultTab: ObservationResultTab
    sidePanelContext: SidePanelSceneContext
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayObservationSceneLogicActions {
    setObservationId: (observationId: string) => {
        observationId: string
    }
    setObservationStatus: (observationStatus: ObservationStatusEnumApi) => {
        observationStatus: ObservationStatusEnumApi
    }
    setParentBreadcrumb: (parentBreadcrumb: Breadcrumb | null) => {
        parentBreadcrumb: Breadcrumb | null
    }
    setResultTab: (resultTab: ObservationResultTab) => {
        resultTab: ObservationResultTab
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayObservationSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        breadcrumbs: (observationId: string, parentBreadcrumb: Breadcrumb | null) => Breadcrumb[]
        sidePanelContext: (
            observationId: string,
            observationStatus: ObservationStatusEnumApi | null
        ) => SidePanelSceneContext
    }
}

export type replayObservationSceneLogicType = MakeLogicType<
    replayObservationSceneLogicValues,
    replayObservationSceneLogicActions,
    Record<string, any>,
    replayObservationSceneLogicMeta
>

export const replayObservationSceneLogic = kea<replayObservationSceneLogicType>([
    path(['products', 'replay_vision', 'frontend', 'observations', 'replayObservationSceneLogic']),

    actions({
        setObservationId: (observationId: string) => ({ observationId }),
        // Pushed by replayObservationLogic once the observation loads. The scene's back button returns
        // to this crumb, so where it points decides where "back" lands.
        setParentBreadcrumb: (parentBreadcrumb: Breadcrumb | null) => ({ parentBreadcrumb }),
        setResultTab: (resultTab: ObservationResultTab) => ({ resultTab }),
        // Pushed by replayObservationLogic too, so the discussion panel knows whether notes are allowed.
        setObservationStatus: (observationStatus: ObservationStatusEnumApi) => ({ observationStatus }),
    }),

    reducers({
        observationId: [
            '' as string,
            {
                setObservationId: (_, { observationId }) => observationId,
            },
        ],
        parentBreadcrumb: [
            null as Breadcrumb | null,
            {
                setParentBreadcrumb: (_, { parentBreadcrumb }) => parentBreadcrumb,
                // Clear when navigating to a different observation so we don't briefly show the previous parent.
                setObservationId: () => null,
            },
        ],
        observationStatus: [
            null as ObservationStatusEnumApi | null,
            {
                setObservationStatus: (_, { observationStatus }) => observationStatus,
                setObservationId: () => null,
            },
        ],
        // Kept across previous and next, so a reviewer can page through timelines.
        resultTab: [
            'summary' as ObservationResultTab,
            {
                setResultTab: (_, { resultTab }) => resultTab,
            },
        ],
    }),

    selectors({
        breadcrumbs: [
            (s) => [s.observationId, s.parentBreadcrumb],
            (observationId: string, parentBreadcrumb: Breadcrumb | null): Breadcrumb[] => [
                VISION_ROOT_BREADCRUMB,
                ...(parentBreadcrumb ? [parentBreadcrumb] : []),
                {
                    key: observationId ? `observation-${observationId}` : 'observation',
                    name: 'Observation',
                    path: urls.replayVisionObservation(observationId),
                },
            ],
        ],
        [SIDE_PANEL_CONTEXT_KEY]: [
            (s) => [s.observationId, s.observationStatus],
            (observationId: string, observationStatus: ObservationStatusEnumApi | null): SidePanelSceneContext => ({
                activity_scope: ActivityScope.REPLAY_OBSERVATION,
                activity_item_id: observationId,
                // A retry deletes an unfinished scan and gives the new scan a new id, which would strand its notes.
                discussions_disabled: observationStatus !== 'succeeded',
            }),
        ],
    }),

    urlToAction(({ actions, values }) => ({
        [urls.replayVisionObservation(':observationId')]: ({ observationId }) => {
            const next = observationId || ''
            if (next !== values.observationId) {
                actions.setObservationId(next)
            }
        },
    })),

    // Siblings opened within the scene still read the page; a later deep link must not seed a stale row.
    beforeUnmount(() => {
        lastObservationsPage.current = null
    }),
])
