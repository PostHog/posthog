export type ObservationResultTab = 'summary' | 'timeline'

export interface ObservationsPage {
    rows: ReplayObservationApi[]
    number: number
    pageSize: number
    total: number
    filterParams: VisionObservationsRetrieveParams
}

/** Why notes are off for an observation, or null when they are on. */
export function observationNotesDisabledReason(status: ObservationStatusEnumApi | null): string | null {
    if (status === 'succeeded') {
        return null
    }
    if (status === null) {
        return 'Loading the observation...'
    }
    // A retry deletes an unfinished scan and gives the new scan a new id, which would strand its notes.
    return status === 'pending' || status === 'running'
        ? 'You can add notes when the scan finishes.'
        : 'You can add notes after the scan succeeds. A retry replaces this scan, so notes on it would be lost.'
}

/** The notes button label. The count comes from the side panel's discussion logic, which reads the global
 * scene, so the buttons read it rather than this scene logic connecting to it. */
export function notesButtonLabel(disabledReason: string | null, noteCount: number): string {
    return !disabledReason && noteCount > 0 ? `Notes (${noteCount})` : 'Notes'
}

/** The page the scanner table last loaded, so a row opened from it paints before its own read lands. */
export const lastObservationsPage: { current: ObservationsPage | null } = { current: null }

