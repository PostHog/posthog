import { MakeLogicType, actions, kea, listeners, path, reducers, selectors } from 'kea'

import { CORE_FILTER_DEFINITIONS_BY_GROUP } from '~/taxonomy/taxonomy'

/** Referrer and campaign lead, because the first thing a reader compares across observations is where the session came from. */
export const DEFAULT_PINNED_PROPERTIES = [
    '$entry_referring_domain',
    '$channel_type',
    '$entry_utm_source',
    '$entry_current_url',
]

/** Sessions this product scans are never longer than a working day, so a few pins is the useful range. */
export const MAX_PINNED_PROPERTIES = 8

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface observationPinnedPropertiesLogicValues {
    pinnedProperties: string[]
    queryablePinnedProperties: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface observationPinnedPropertiesLogicActions {
    setPinnedProperties: (properties: string[]) => {
        properties: string[]
    }
    togglePropertyPin: (propertyKey: string) => {
        propertyKey: string
    }
    resetPinnedProperties: () => void
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface observationPinnedPropertiesLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        queryablePinnedProperties: (pinnedProperties: string[]) => string[]
    }
}

export type observationPinnedPropertiesLogicType = MakeLogicType<
    observationPinnedPropertiesLogicValues,
    observationPinnedPropertiesLogicActions,
    Record<string, any>,
    observationPinnedPropertiesLogicMeta
>

/**
 * Which session properties the observation page shows in its pinned strip. Browser-local, so the picks
 * follow one person across scanners rather than being scoped to a scanner or shared with the team.
 */
export const observationPinnedPropertiesLogic = kea<observationPinnedPropertiesLogicType>([
    path(['products', 'replay_vision', 'frontend', 'observations', 'observationPinnedPropertiesLogic']),

    actions({
        setPinnedProperties: (properties: string[]) => ({ properties }),
        togglePropertyPin: (propertyKey: string) => ({ propertyKey }),
        resetPinnedProperties: () => ({}),
    }),

    reducers({
        pinnedProperties: [
            DEFAULT_PINNED_PROPERTIES as string[],
            { persist: true },
            {
                setPinnedProperties: (_, { properties }) => properties.slice(0, MAX_PINNED_PROPERTIES),
                resetPinnedProperties: () => DEFAULT_PINNED_PROPERTIES,
            },
        ],
    }),

    selectors({
        queryablePinnedProperties: [
            (s) => [s.pinnedProperties],
            // A stored pin the sessions table doesn't have would fail the whole query, taking the other pins with it.
            (pinnedProperties: string[]): string[] =>
                pinnedProperties.filter((property) =>
                    Object.hasOwn(CORE_FILTER_DEFINITIONS_BY_GROUP.session_properties, property)
                ),
        ],
    }),

    listeners(({ actions, values }) => ({
        togglePropertyPin: ({ propertyKey }) => {
            const pinned = values.pinnedProperties
            actions.setPinnedProperties(
                pinned.includes(propertyKey) ? pinned.filter((key) => key !== propertyKey) : [...pinned, propertyKey]
            )
        },
    })),
])
