interface DisplayState {
    step: number
    /** Client-clock ms when the current display step started. */
    startedAt: number
}

interface RememberedProgress {
    progress: ObservationProgress | null
    display: DisplayState | null
    percent: number
}

// Survives unmount so a reopened tab or dock resumes the bar instead of restarting it.
const progressMemory = new Map<string, RememberedProgress>()

function rememberedProgress(observationId: string): RememberedProgress {
    return progressMemory.get(observationId) ?? { progress: null, display: null, percent: 0 }
}

const PROGRESS_TICK_MS = 1000
const RECONNECT_INITIAL_DELAY_MS = 2000
const RECONNECT_MAX_DELAY_MS = 30000

export interface ObservationProgressLogicProps {
    observationId: string
    /** Lets the dock list refresh on completion; optional since the details page has no dock. */
    sessionId?: string
}

interface StreamHandlers {
    setProgress: (progress: ObservationProgress) => void
    streamCompleted: () => void
    setStreamError: (error: string) => void
}

/** Parse one SSE block (`event: <label>\ndata: <json>`) from our progress endpoint and dispatch it. */
function dispatchSseBlock(block: string, handlers: StreamHandlers): void {
    let event = ''
    const dataLines: string[] = []
    for (const line of block.split('\n')) {
        if (line.startsWith('event:')) {
            event = line.slice('event:'.length).trim()
        } else if (line.startsWith('data:')) {
            dataLines.push(line.slice('data:'.length).replace(/^ /, ''))
        }
    }
    const data = dataLines.join('\n')
    if (event === 'observation-progress') {
        try {
            handlers.setProgress(JSON.parse(data))
        } catch {
            // Drop an unparseable tick; the next one refreshes the bar.
        }
    } else if (event === 'observation-complete') {
        handlers.streamCompleted()
    } else if (event === 'observation-error') {
        handlers.setStreamError(data)
    }
}

async function consumeProgressStream(
    teamId: number,
    observationId: string,
    signal: AbortSignal,
    handlers: StreamHandlers
): Promise<boolean> {
    // Plain GET so read-only users can stream too (api.createResponse POSTs, which is blocked for them).
    const response = await fetch(`/api/projects/${teamId}/vision/observations/${observationId}/progress/`, {
        method: 'GET',
        headers: { Accept: 'text/event-stream' },
        credentials: 'same-origin',
        signal,
    })
    if (!response.ok || !response.body) {
        return false
    }
    const reader = response.body.getReader()
    const decoder = new TextDecoder()
    let buffer = ''
    let received = false
    while (true) {
        const { done, value } = await reader.read()
        if (done) {
            return received
        }
        buffer += decoder.decode(value, { stream: true })
        let boundary = buffer.indexOf('\n\n')
        while (boundary !== -1) {
            received = true
            dispatchSseBlock(buffer.slice(0, boundary), handlers)
            buffer = buffer.slice(boundary + 2)
            boundary = buffer.indexOf('\n\n')
        }
    }
}

function waitFor(ms: number, signal: AbortSignal): Promise<void> {
    return new Promise((resolve) => {
        const onAbort = (): void => {
            clearTimeout(timer)
            resolve()
        }
        const timer = setTimeout(() => {
            signal.removeEventListener('abort', onAbort)
            resolve()
        }, ms)
        signal.addEventListener('abort', onAbort, { once: true })
    })
}

/** The server caps stream length and proxies drop idle streams, so any close short of a terminal event reconnects. */
async function followProgressStream(
    teamId: number,
    observationId: string,
    signal: AbortSignal,
    handlers: StreamHandlers
): Promise<void> {
    let delayMs = RECONNECT_INITIAL_DELAY_MS
    while (!signal.aborted) {
        let received = false
        try {
            received = await consumeProgressStream(teamId, observationId, signal, handlers)
        } catch {
            // An abort ends the loop; other errors reconnect.
        }
        delayMs = received ? RECONNECT_INITIAL_DELAY_MS : Math.min(delayMs * 2, RECONNECT_MAX_DELAY_MS)
        await waitFor(delayMs, signal)
    }
}

