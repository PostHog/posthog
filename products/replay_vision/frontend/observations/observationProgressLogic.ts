/**
 * Streams live progress for one in-flight observation over SSE. Keyed by observation id, so the dock card and the
 * details page share a single stream. The stream self-terminates once the observation settles.
 */
export const observationProgressLogic = kea<observationProgressLogicType>([
    path(['products', 'replay_vision', 'frontend', 'observations', 'observationProgressLogic']),
    props({} as ObservationProgressLogicProps),
    key((props) => props.observationId),

    actions({
        // Idempotent — callers that know the observation is in flight open the stream; settled rows never do.
        startStream: true,
        setProgress: (progress: ObservationProgress, receivedAt: number = Date.now()) => ({ progress, receivedAt }),
        tick: (now: number = Date.now()) => ({ now }),
        setPercent: (percent: number) => ({ percent }),
        streamCompleted: true,
        setStreamError: (error: string) => ({ error }),
    }),

    reducers(({ props }) => ({
        progress: [
            rememberedProgress(props.observationId).progress,
            {
                setProgress: (_, { progress }) => progress,
            },
        ],
        display: [
            rememberedProgress(props.observationId).display,
            {
                setProgress: (state, { progress, receivedAt }) => {
                    const step = displayStepFor(progress)
                    // A stale tick (failed query, render retry) must not pull the bar back.
                    if (state && step <= state.step) {
                        return state
                    }
                    // Rendering is measured in frames, so only time-filled steps need the server's elapsed time.
                    const elapsedMs = isRenderingStep(step) ? 0 : (progress.phase_elapsed_s ?? 0) * 1000
                    return { step, startedAt: receivedAt - elapsedMs }
                },
            },
        ],
        percent: [
            rememberedProgress(props.observationId).percent,
            {
                setPercent: (state, { percent }) => Math.max(state, percent),
            },
        ],
        streamError: [
            null as string | null,
            {
                setStreamError: (_, { error }) => error,
            },
        ],
    })),

    selectors({
        frames: [
            (s) => [s.progress],
            (progress: ObservationProgress | null): ObservationFrameProgress | null => framesOf(progress),
        ],
        displayPhase: [
            (s) => [s.display],
            (display: DisplayState | null): DisplayPhase => DISPLAY_PHASES[display?.step ?? 0],
        ],
        stepNumber: [(s) => [s.display], (display: DisplayState | null): number => (display?.step ?? 0) + 1],
    }),

    listeners(({ props, actions, cache, values }) => ({
        setProgress: ({ receivedAt }) => {
            actions.tick(receivedAt)
        },
        tick: ({ now }) => {
            const { display, frames } = values
            if (display) {
                const elapsedS = (now - display.startedAt) / 1000
                actions.setPercent(overallPercent(display.step, elapsedS, frames))
            }
            progressMemory.set(props.observationId, {
                progress: values.progress,
                display: values.display,
                percent: values.percent,
            })
        },
        startStream: () => {
            const teamId = teamLogic.values.currentTeamId
            if (cache.streamStarted || !teamId) {
                return
            }
            cache.streamStarted = true
            // Disposable so the fetch is aborted on unmount and paused while the tab is hidden.
            cache.disposables.add(() => {
                const controller = new AbortController()
                void followProgressStream(teamId, props.observationId, controller.signal, actions)
                return () => controller.abort()
            }, 'progressStream')
            cache.disposables.add(() => {
                const interval = setInterval(() => actions.tick(), PROGRESS_TICK_MS)
                return () => clearInterval(interval)
            }, 'progressTicker')
        },
        streamCompleted: () => {
            // The observation settled — dispose the stream so tab hide/show cycles don't resurrect it.
            cache.disposables.dispose('progressStream')
            cache.disposables.dispose('progressTicker')
            progressMemory.delete(props.observationId)
            // Refresh the dock list so the finished card swaps to the result immediately; no-op if the dock isn't mounted.
            if (props.sessionId) {
                observationsDockLogic.findMounted({ sessionId: props.sessionId })?.actions.loadObservations()
            }
        },
        setStreamError: () => {
            cache.disposables.dispose('progressStream')
            cache.disposables.dispose('progressTicker')
        },
    })),
])
