import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { getTimestampFromUUIDv7 } from 'scenes/sessions/sessionProfileLogic'

import { QueryLogTags } from '~/queries/schema/schema-general'
import { HogQLQueryString, escapePropertyAsHogQLIdentifier, hogql } from '~/queries/utils'

import { PinnedProperty, observationPinnedPropertiesLogic } from './observationPinnedPropertiesLogic'

const QUERY_TAGS: QueryLogTags = { scene: 'ReplayVisionObservation', productKey: 'replay_vision' }

export interface ObservationSessionPropertiesLogicProps {
    sessionId: string
}

/** Identifies a pin in the response map, since the same key can be pinned from two namespaces. */
export function pinnedPropertyId(property: PinnedProperty): string {
    return `${property.type}:${property.key}`
}

function selectExpression(property: PinnedProperty): string {
    const identifier = escapePropertyAsHogQLIdentifier(property.key)
    if (property.type === 'session') {
        return `session.${identifier}`
    }
    if (property.type === 'person') {
        return `person.properties.${identifier}`
    }
    return `properties.${identifier}`
}

function buildQuery(sessionId: string, properties: PinnedProperty[]): HogQLQueryString {
    // Positional aliases, because the same key can be pinned from two namespaces and would collide.
    const selects = properties
        .map((property, index) => `any(${selectExpression(property)}) as pinned_${index}`)
        .join(', ')
    const { startDate, endDate } = getTimestampFromUUIDv7(sessionId)
    return hogql`
        SELECT ${hogql.raw(selects)}
        FROM events
        WHERE $session_id = ${sessionId}
            AND timestamp >= toDateTime(${startDate.toISOString()})
            AND timestamp <= toDateTime(${endDate.toISOString()})`
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface observationSessionPropertiesLogicValues {
    queryablePinnedProperties: PinnedProperty[] // observationPinnedPropertiesLogic
    sessionProperties: Record<string, string | null> | null
    sessionPropertiesLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface observationSessionPropertiesLogicActions {
    setPinnedProperties: (properties: PinnedProperty[]) => {
        properties: PinnedProperty[]
    } // observationPinnedPropertiesLogic
    loadSessionProperties: () => void
    loadSessionPropertiesSuccess: (sessionProperties: Record<string, string | null> | null) => {
        sessionProperties: Record<string, string | null> | null
    }
    loadSessionPropertiesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
}

export type observationSessionPropertiesLogicType = MakeLogicType<
    observationSessionPropertiesLogicValues,
    observationSessionPropertiesLogicActions,
    ObservationSessionPropertiesLogicProps
>

/**
 * Reads the pinned properties for one observed session. One pass over the session's events serves
 * all three namespaces: session columns, event property bags, and the person behind the session.
 */
export const observationSessionPropertiesLogic = kea<observationSessionPropertiesLogicType>([
    path(['products', 'replay_vision', 'frontend', 'observations', 'observationSessionPropertiesLogic']),
    props({} as ObservationSessionPropertiesLogicProps),
    key((props) => props.sessionId),

    connect(() => ({
        values: [observationPinnedPropertiesLogic, ['queryablePinnedProperties']],
        actions: [observationPinnedPropertiesLogic, ['setPinnedProperties']],
    })),

    loaders(({ props, values }) => ({
        sessionProperties: [
            null as Record<string, string | null> | null,
            {
                loadSessionProperties: async (_, breakpoint) => {
                    const properties = values.queryablePinnedProperties
                    if (!props.sessionId || !properties.length) {
                        return null
                    }
                    await breakpoint(100)

                    let response
                    try {
                        response = await api.queryHogQL(buildQuery(props.sessionId, properties), QUERY_TAGS)
                    } catch (e) {
                        // This strip is supplementary context. A failed read should leave it empty, not toast over the result.
                        posthog.captureException(e)
                        return null
                    }
                    breakpoint()

                    const row = response.results?.[0]
                    if (!row) {
                        return null
                    }
                    return Object.fromEntries(
                        // An event carrying the key with an empty value reads the same as never carrying it.
                        properties.map((property, index) => [pinnedPropertyId(property), row[index] || null])
                    )
                },
            },
        ],
    })),

    listeners(({ actions }) => ({
        // A newly pinned property isn't in the last response, so the row has to be read again.
        setPinnedProperties: () => actions.loadSessionProperties(),
    })),

    afterMount(({ actions }) => {
        actions.loadSessionProperties()
    }),
])
