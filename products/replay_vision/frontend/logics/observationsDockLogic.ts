export const observationsDockLogic = kea<observationsDockLogicType>([
    path(['products', 'replay_vision', 'frontend', 'logics', 'observationsDockLogic']),
    props({} as ObservationsDockLogicProps),
    key((props) => props.sessionId),

    connect(() => ({
        // The scanner list is team-wide — shared so per-recording dock instances don't each refetch it.
        values: [
            visionScannersListLogic,
            ['scanners', 'scannersLoading'],
            visionDockPreferenceLogic,
            ['summaryDockAutoExpand'],
        ],
        actions: [visionDockPreferenceLogic, ['setSummaryDockAutoExpand']],
    })),

    actions({
        loadObservations: true,
        loadObservationsSuccess: (observations: ReplayObservationApi[]) => ({ observations }),
        loadObservationsFailure: true,
        observe: (scannerId: string) => ({ scannerId }),
        observeSuccess: true,
        observeFailure: true,
        retryObservation: (observationId: string) => ({ observationId }),
        retryObservationSuccess: (observationId: string) => ({ observationId }),
        retryObservationFailure: (observationId: string) => ({ observationId }),
        setDockOpen: (open: boolean) => ({ open }),
        setScannerPickerOpen: (open: boolean) => ({ open }),
        setScannerSearch: (search: string) => ({ search }),
        summarize: true,
        summarizeSuccess: true,
        summarizeFailure: true,
    }),

    reducers({
        observations: [
            [] as ReplayObservationApi[],
            {
                loadObservationsSuccess: (_, { observations }) => observations,
            },
        ],
        observationsLoading: [
            false,
            {
                loadObservations: () => true,
                loadObservationsSuccess: () => false,
                loadObservationsFailure: () => false,
            },
        ],
        observing: [
            false,
            {
                observe: () => true,
                observeSuccess: () => false,
                observeFailure: () => false,
            },
        ],
        summarizing: [
            false,
            {
                summarize: () => true,
                summarizeSuccess: () => false,
                summarizeFailure: () => false,
            },
        ],
        dockOpen: [
            false,
            {
                setDockOpen: (_, { open }) => open,
            },
        ],
        scannerPickerOpen: [
            false,
            {
                setScannerPickerOpen: (_, { open }) => open,
            },
        ],
        scannerSearch: [
            '',
            {
                setScannerSearch: (_, { search }) => search,
                // Reset the query each time the picker is opened or closed.
                setScannerPickerOpen: () => '',
            },
        ],
        retryingObservationIds: [
            [] as string[],
            {
                retryObservation: (state: string[], { observationId }: { observationId: string }) => [
                    ...state,
                    observationId,
                ],
                retryObservationSuccess: (state: string[], { observationId }: { observationId: string }) =>
                    state.filter((id) => id !== observationId),
                retryObservationFailure: (state: string[], { observationId }: { observationId: string }) =>
                    state.filter((id) => id !== observationId),
            },
        ],
        pollUntil: [
            0,
            {
                observeSuccess: () => Date.now() + OBSERVE_POLL_GRACE_MS,
                summarizeSuccess: () => Date.now() + OBSERVE_POLL_GRACE_MS,
                // The replacement row is inserted by the workflow moments after the retry 202 lands.
                retryObservationSuccess: () => Date.now() + OBSERVE_POLL_GRACE_MS,
            },
        ],
    }),

    selectors({
        hasObservationsInFlight: [
            (s) => [s.observations],
            (observations: ReplayObservationApi[]): boolean =>
                observations.some((o) => o.status === 'pending' || o.status === 'running'),
        ],
        seekbarMarks: [
            (s) => [s.observations],
            (observations: ReplayObservationApi[]): ObservationSeekbarMark[] => observationSeekbarMarks(observations),
        ],
        filteredScanners: [
            (s) => [s.scanners, s.scannerSearch],
            (scanners: ReplayScannerApi[], scannerSearch: string): ReplayScannerApi[] => {
                const query = scannerSearch.trim().toLowerCase()
                return query ? scanners.filter((scanner) => scanner.name.toLowerCase().includes(query)) : scanners
            },
        ],
    }),

    listeners(({ actions, props, values, cache }) => {
        const reschedulePoll = (): void => {
            scheduleObservationPoll(
                cache.disposables,
                shouldPollObservations(values.hasObservationsInFlight, values.pollUntil),
                actions.loadObservations
            )
        }
        // A summary is only readable once the dock is open, so a recording that already has one opens it
        // rather than hiding it behind the caret. Collapsing the dock turns this off until it is expanded
        // again, otherwise the next recording in the playlist would re-open what the user just closed.
        const openDockForExistingSummary = (): void => {
            if (values.dockOpen || !values.summaryDockAutoExpand) {
                return
            }
            if (values.observations.some((o) => isSummaryObservation(o) && o.status === 'succeeded')) {
                actions.setDockOpen(true)
            }
        }
        // Show the row that is coming, and re-read the quota the scan spent. Only call this when a scan
        // actually started, or the poll window opens for work that will never land.
        const afterScanStarted = (): void => {
            actions.loadObservations()
            refreshVisionQuota()
        }
        const reportTriggerFailure = (error: unknown, metric: string, message: string): void => {
            metricCount(metric)
            const detail = error instanceof ApiError && error.detail ? `: ${error.detail}` : ''
            lemonToast.error(`${message}${detail}`)
        }
        return {
            loadObservations: async (_, breakpoint) => {
                // Poll, observe, retry, and the SSE hook all call this; without it a slow earlier response
                // lands last and resurrects a settled card.
                await breakpoint(1)
                const teamId = teamLogic.values.currentTeamId
                if (!teamId) {
                    actions.loadObservationsFailure() // Clear the loading flag; a bare return spins forever.
                    return
                }
                try {
                    const response = await visionObservationsList(String(teamId), { session_id: props.sessionId })
                    breakpoint()
                    actions.loadObservationsSuccess(response.results ?? [])
                } catch {
                    metricCount('replay_vision_frontend_observations_load_failures')
                    actions.loadObservationsFailure()
                }
            },

            // Poll while in flight and through the observe grace window; rescheduled on failure so one hiccup can't kill it.
            loadObservationsSuccess: () => {
                openDockForExistingSummary()
                reschedulePoll()
            },
            loadObservationsFailure: reschedulePoll,

            // Every open and close runs through here, so the preference tracks the last one the user made.
            setDockOpen: ({ open }) => actions.setSummaryDockAutoExpand(open),

            observe: async ({ scannerId }) => {
                // A cache flag, not `values.observing`: the reducer has already flipped that to true by the
                // time this listener runs, so it would reject every call.
                if (cache.observeInFlight) {
                    return
                }
                actions.setScannerPickerOpen(false)
                const teamId = teamLogic.values.currentTeamId
                if (!teamId) {
                    actions.observeFailure()
                    return
                }
                // Backend keys the workflow id on (scanner, session); re-triggering the same pair silently no-ops.
                if (values.observations.some((o) => o.scanner_id === scannerId)) {
                    lemonToast.info('This scanner has already been run on this recording.')
                    actions.observeFailure()
                    actions.setDockOpen(true)
                    return
                }
                cache.observeInFlight = true
                try {
                    await visionScannersObserveCreate(String(teamId), scannerId, { session_id: props.sessionId })
                    lemonToast.success('Observation started')
                    actions.observeSuccess()
                    afterScanStarted()
                } catch (error) {
                    // Counted here rather than on observeFailure, which also fires for benign
                    // paths (scanner already run, no team) that would pollute the failure rate.
                    reportTriggerFailure(
                        error,
                        'replay_vision_frontend_observe_failures',
                        'Failed to start observation'
                    )
                    actions.observeFailure()
                } finally {
                    cache.observeInFlight = false
                }
            },

            summarize: async () => {
                // A cache flag for the same reason `observe` uses one: the reducer has already flipped
                // `summarizing` by the time this runs.
                if (cache.summarizeInFlight) {
                    return
                }
                const teamId = teamLogic.values.currentTeamId
                if (!teamId) {
                    actions.summarizeFailure()
                    return
                }
                cache.summarizeInFlight = true
                try {
                    const response = await visionScannersInlineScanCreate(String(teamId), {
                        ...SUMMARIZE_RECORDING_CONFIG,
                        session_ids: [props.sessionId],
                    })
                    // One session in, so one result out. The inline scanner is shared per project, so a
                    // recording somebody already summarized comes back settled instead of started.
                    const outcome = response.results?.[0]?.scan_outcome
                    if (outcome === 'already_scanned') {
                        // A row settled server-side, but the inline scanner is shared and RBAC-scoped, so
                        // the row may not be readable here, and the reload can also fail. Confirm the row
                        // is in hand before naming it, and leave a way to re-read when it stays hidden.
                        actions.summarizeFailure()
                        actions.setDockOpen(true)
                        const tryAgain = { label: 'Try again', action: () => actions.loadObservations() }
                        try {
                            const reloaded = await visionObservationsList(String(teamId), {
                                session_id: props.sessionId,
                            })
                            const results = reloaded.results ?? []
                            actions.loadObservationsSuccess(results)
                            if (response.scan_id && results.some((o) => o.scanner_id === response.scan_id)) {
                                // The row is readable below. A failed or ineligible one still shows its retry
                                // control there, so the user has a way to run the summary again.
                                lemonToast.info('This recording already has a result below.')
                            } else {
                                lemonToast.warning(
                                    'This recording was already summarized, but the result is not available here.',
                                    { button: tryAgain }
                                )
                            }
                        } catch {
                            metricCount('replay_vision_frontend_observations_load_failures')
                            actions.loadObservationsFailure()
                            lemonToast.warning("Couldn't load this recording's summary.", { button: tryAgain })
                        }
                        return
                    }
                    const { level, message } = summarizeOutcomeMessage(outcome)
                    lemonToast[level](message)
                    if (outcome === 'started' || outcome === 'already_running') {
                        // A scan is in flight either way — ours, or one this project already had running
                        // against the shared inline scanner — so the poll window has a row to wait for.
                        actions.summarizeSuccess()
                        actions.setDockOpen(true)
                        afterScanStarted()
                    } else {
                        // Nothing started and nothing to read, so the poll window would watch for a row
                        // that never arrives.
                        actions.summarizeFailure()
                    }
                } catch (error) {
                    reportTriggerFailure(
                        error,
                        'replay_vision_frontend_summarize_failures',
                        'Failed to summarize recording'
                    )
                    actions.summarizeFailure()
                } finally {
                    cache.summarizeInFlight = false
                }
            },

            retryObservation: async ({ observationId }) => {
                if (!(await requestObservationRetry(observationId))) {
                    actions.retryObservationFailure(observationId)
                    return
                }
                actions.retryObservationSuccess(observationId)
                actions.loadObservations()
            },
        }
    }),

    afterMount(({ actions }) => {
        actions.loadObservations()
    }),
])
