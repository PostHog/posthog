import { MakeLogicType, afterMount, connect, kea, listeners, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import { teamLogic } from 'scenes/teamLogic'

import { NodeKind } from '~/queries/schema/schema-general'
import type { TeamPublicType, TeamType } from '~/types'

export const RECENT_RECORDINGS_DAYS = 30
// Matches Session Replay's own setup check, so a page left open flips once the first recording lands.
const POLL_INTERVAL_MS = 20000

export type RecordingsBlock = 'replay-off' | 'no-recordings'

export const RECORDINGS_BLOCK_CAUSE: Record<RecordingsBlock, string> = {
    'replay-off': 'Session replay is off for this project',
    'no-recordings': `This project has no recordings from the last ${RECENT_RECORDINGS_DAYS} days`,
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayRecordingsLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    hasRecentRecordings: boolean | null
    hasRecentRecordingsLoading: boolean
    recordingsBlock: RecordingsBlock | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayRecordingsLogicActions {
    updateCurrentTeamSuccess: (
        currentTeam: TeamPublicType | TeamType,
        payload?: Partial<TeamType> | undefined
    ) => {
        currentTeam: TeamPublicType | TeamType
        payload?: Partial<TeamType>
    } // teamLogic
    loadHasRecentRecordings: () => any
    loadHasRecentRecordingsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadHasRecentRecordingsSuccess: (
        hasRecentRecordings: boolean | null,
        payload?: any
    ) => {
        hasRecentRecordings: boolean | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayRecordingsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        recordingsBlock: (
            currentTeam: TeamPublicType | TeamType | null,
            hasRecentRecordings: boolean | null
        ) => RecordingsBlock | null
    }
}

export type replayRecordingsLogicType = MakeLogicType<
    replayRecordingsLogicValues,
    replayRecordingsLogicActions,
    Record<string, any>,
    replayRecordingsLogicMeta
>

/** Propless, so every Replay Vision surface shares one probe. */
export const replayRecordingsLogic = kea<replayRecordingsLogicType>([
    path(['products', 'replay_vision', 'frontend', 'logics', 'replayRecordingsLogic']),

    connect(() => ({
        values: [teamLogic, ['currentTeam']],
        actions: [teamLogic, ['updateCurrentTeamSuccess']],
    })),

    loaders({
        hasRecentRecordings: [
            // Null until the probe answers. A failed probe stays null, so no surface warns on a guess.
            null as boolean | null,
            {
                loadHasRecentRecordings: async (): Promise<boolean | null> => {
                    try {
                        const response = await api.recordings.list({
                            kind: NodeKind.RecordingsQuery,
                            limit: 1,
                            date_from: `-${RECENT_RECORDINGS_DAYS}d`,
                        })
                        return response.results.length > 0
                    } catch {
                        return null
                    }
                },
            },
        ],
    }),

    selectors({
        recordingsBlock: [
            (s) => [s.currentTeam, s.hasRecentRecordings],
            (
                currentTeam: TeamPublicType | TeamType | null,
                hasRecentRecordings: boolean | null
            ): RecordingsBlock | null => {
                if (currentTeam?.session_recording_opt_in === false) {
                    return 'replay-off'
                }
                return hasRecentRecordings === false ? 'no-recordings' : null
            },
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        loadHasRecentRecordingsSuccess: ({ hasRecentRecordings }) => {
            if (hasRecentRecordings === false) {
                cache.disposables.add(() => {
                    const id = window.setInterval(() => actions.loadHasRecentRecordings(), POLL_INTERVAL_MS)
                    return () => clearInterval(id)
                }, 'poll')
            } else {
                cache.disposables.dispose('poll')
            }
        },
        // Turning recording on from the banner does not remount this logic, so the skipped probe runs now.
        updateCurrentTeamSuccess: ({ currentTeam }) => {
            if (currentTeam?.session_recording_opt_in && values.hasRecentRecordings === null) {
                actions.loadHasRecentRecordings()
            }
        },
    })),

    afterMount(({ actions, values }) => {
        // With recording off the block is already known, so the probe would only spend a query.
        if (values.currentTeam?.session_recording_opt_in !== false) {
            actions.loadHasRecentRecordings()
        }
    }),
])
