// This event carries no query property. The text is free and can hold customer names or emails.
// The `q` URL parameter still reaches analytics through `$current_url`, as it does for every event on this page.
function captureSearchOutcome(
    scannerId: string | null,
    outcome: { succeeded: boolean; result_count?: number; error_status?: number; error_code?: string }
): void {
    posthog.capture('replay vision observation search completed', {
        ...outcome,
        scope: scannerId ? 'scanner' : 'cross-scanner',
    })
}

export const observationSearchLogic = kea<observationSearchLogicType>([
    path(['products', 'replay_vision', 'frontend', 'search', 'observationSearchLogic']),
    props({} as ObservationSearchLogicProps),
    key((props) => `${props.userId ?? 'user'}:${props.teamId ?? 'team'}`),

    actions({
        setQuery: (query: string) => ({ query }),
        setScannerId: (scannerId: string | null) => ({ scannerId }),
        setPage: (page: number) => ({ page }),
        setView: (view: ResultsView) => ({ view }),
        search: true,
        searchSimilar: (query: string, sourceObservationId: string) => ({ query, sourceObservationId }),
        searchSuccess: (
            results: ObservationSearchResultApi[],
            query: string,
            truncated: boolean,
            sourceObservationId: string | null = null
        ) => ({
            results,
            query,
            truncated,
            sourceObservationId,
        }),
        searchFailure: true,
        clearSearch: true,
    }),

    reducers({
        query: [
            '' as string,
            {
                setQuery: (_, { query }) => query,
                searchSimilar: (_, { query }) => query,
                clearSearch: () => '',
            },
        ],
        scannerId: [
            null as string | null,
            {
                setScannerId: (_, { scannerId }) => scannerId,
            },
        ],
        // Provenance of the next search. Editing the prose makes it a regular search.
        pendingSourceObservationId: [
            null as string | null,
            {
                searchSimilar: (_, { sourceObservationId }) => sourceObservationId,
                setQuery: () => null,
                clearSearch: () => null,
            },
        ],
        // Provenance of the displayed results, so their links keep the prose out of the URL until a new search lands.
        sourceObservationId: [
            null as string | null,
            {
                searchSuccess: (_, { sourceObservationId }) => sourceObservationId,
                clearSearch: () => null,
            },
        ],
        // null until the first search, so the empty state can tell "not searched yet" from "no matches".
        results: [
            null as ObservationSearchResultApi[] | null,
            {
                searchSuccess: (_, { results }) => results,
                clearSearch: () => null,
            },
        ],
        searching: [
            false,
            {
                search: () => true,
                searchSuccess: () => false,
                searchFailure: () => false,
                clearSearch: () => false,
            },
        ],
        searchedQuery: [
            null as string | null,
            {
                searchSuccess: (_, { query }) => query,
                clearSearch: () => null,
            },
        ],
        recentQueries: [
            [] as string[],
            { persist: true },
            {
                searchSuccess: (state, { query, results, sourceObservationId }) =>
                    sourceObservationId === null && results.length > 0
                        ? [query, ...state.filter((recent) => recent !== query)].slice(0, RECENT_QUERIES_LIMIT)
                        : state,
            },
        ],
        page: [
            1 as number,
            {
                setPage: (_, { page }) => page,
                searchSuccess: () => 1,
            },
        ],
        view: [
            'grid' as ResultsView,
            { persist: true },
            {
                setView: (_, { view }) => view,
            },
        ],
        // The server cut the response to `limit`, so the results are a top slice, not everything that matched.
        truncated: [
            false,
            {
                searchSuccess: (_, { truncated }) => truncated,
                clearSearch: () => false,
            },
        ],
    }),

    loaders(({ values }) => ({
        suggestedQueries: [
            [] as string[],
            {
                loadSuggestedQueries: async (_: void, breakpoint) => {
                    await breakpoint(SEARCH_COALESCE_MS)
                    const teamId = teamLogic.values.currentTeamId
                    // A deep-linked query renders results, never the empty state, so its suggestions would go unseen.
                    if (!teamId || router.values.searchParams.q) {
                        return []
                    }
                    const scope = values.scannerId ? { scanner_id: values.scannerId } : undefined
                    // The view is what keeps a scanner's suggestions refreshing; it is a separate POST so the read
                    // stays side-effect free, and nothing here waits on it.
                    void visionObservationsSearchViewedCreate(String(teamId), scope).catch(() => undefined)
                    try {
                        const response = await visionObservationsSearchSuggestionsRetrieve(String(teamId), scope)
                        return response.queries ?? []
                    } catch {
                        // The empty state falls back to fixed examples, so a failed suggestion fetch stays silent.
                        return []
                    }
                },
            },
        ],
    })),

    selectors({
        pageCount: [
            (s) => [s.results],
            (results: ObservationSearchResultApi[] | null): number =>
                results ? Math.ceil(results.length / SEARCH_PAGE_SIZE) : 0,
        ],
        pageResults: [
            (s) => [s.results, s.page],
            (results: ObservationSearchResultApi[] | null, page: number): ObservationSearchResultApi[] =>
                results ? results.slice((page - 1) * SEARCH_PAGE_SIZE, page * SEARCH_PAGE_SIZE) : [],
        ],
        pageStartIndex: [(s) => [s.page], (page: number): number => (page - 1) * SEARCH_PAGE_SIZE],
        pageEndIndex: [
            (s) => [s.pageStartIndex, s.pageResults],
            (pageStartIndex: number, pageResults: ObservationSearchResultApi[]): number =>
                pageStartIndex + pageResults.length,
        ],
        // Null when the tiers would not separate anything, so a lone tier is never labeled.
        topMatchDistanceCutoff: [
            (s) => [s.results],
            (results: ObservationSearchResultApi[] | null): number | null => {
                if (!results || results.length < 2) {
                    return null
                }
                const cutoff = Math.min(...results.map((r) => r.distance)) + TOP_MATCH_MARGIN
                return results.some((r) => r.distance > cutoff) ? cutoff : null
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        // Emptying the input (the field's clear button included) is how a person gets back to the empty state.
        setQuery: ({ query }) => {
            if (!query.trim() && values.searchedQuery !== null) {
                actions.clearSearch()
            }
        },
        setScannerId: () => {
            actions.loadSuggestedQueries()
            if (values.searchedQuery !== null || values.searching) {
                actions.search()
            }
        },
        searchSimilar: () => actions.search(),
        search: async (_, breakpoint) => {
            await breakpoint(SEARCH_COALESCE_MS)
            const query = values.query.trim()
            if (!query) {
                actions.searchFailure()
                return
            }
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                actions.searchFailure()
                return
            }
            const sourceObservationId = values.pendingSourceObservationId
            try {
                const response = await visionObservationsSearchRetrieve(String(teamId), {
                    q: query,
                    limit: SEARCH_RESULT_LIMIT,
                    ...(values.scannerId ? { scanner_id: values.scannerId } : {}),
                })
                // Drop out-of-order responses. The newest search owns the results.
                breakpoint()
                // The source of a "find similar" search is its own nearest neighbour.
                const results = (response.results ?? []).filter((r) => r.observation.id !== sourceObservationId)
                captureSearchOutcome(values.scannerId, { succeeded: true, result_count: results.length })
                // Cleared while in flight: the late response must not refill the card.
                if (!values.searching) {
                    return
                }
                actions.searchSuccess(results, query, response.truncated ?? false, sourceObservationId)
            } catch (error: any) {
                if (error instanceof Error && isBreakpoint(error)) {
                    throw error
                }
                // Drop out-of-order failures, like the success path above. A newer search owns the outcome,
                // so an older failure must not skew the capture, raise a toast, or stop the spinner.
                breakpoint()
                captureSearchOutcome(values.scannerId, {
                    succeeded: false,
                    error_status: error?.status,
                    error_code: error?.code,
                })
                if (error?.code === AI_CONSENT_REQUIRED_CODE) {
                    lemonToast.error('AI data processing is turned off for your organization.', {
                        button: {
                            label: 'Open settings',
                            action: () =>
                                router.actions.push(urls.settings('organization-details', 'organization-ai-consent')),
                        },
                    })
                } else {
                    lemonToast.error(`Search failed${error?.detail ? `: ${error.detail}` : ''}`)
                }
                actions.searchFailure()
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadSuggestedQueries()
    }),

    actionToUrl(({ values }) => {
        const withScope = (
            q: string | undefined
        ): [string, Record<string, unknown>, Record<string, unknown>, { replace: boolean }] => [
            router.values.location.pathname,
            {
                ...router.values.searchParams,
                q,
                scanner: values.scannerId ?? undefined,
                similar: values.pendingSourceObservationId ?? undefined,
            },
            router.values.hashParams,
            { replace: true },
        ]
        return {
            // Observation prose stays out of the URL (see markSimilarSearchIntent).
            search: () => withScope(values.pendingSourceObservationId ? undefined : values.query.trim() || undefined),
            clearSearch: () => withScope(undefined),
            setScannerId: () => withScope(router.values.searchParams.q),
        }
    }),

    urlToAction(({ actions, values }) => {
        return {
            [urls.replayVision()]: (_: unknown, searchParams: Record<string, unknown>) => {
                if (searchParams.tab !== ReplayScannerTab.Search) {
                    return
                }
                const scanner = typeof searchParams.scanner === 'string' ? searchParams.scanner : null
                if (scanner !== values.scannerId) {
                    actions.setScannerId(scanner)
                }
                const similar = typeof searchParams.similar === 'string' ? searchParams.similar : ''
                if (similar) {
                    // Result links keep `similar` after typing cleared the pending source, so match the shown source too.
                    if (similar === values.pendingSourceObservationId || similar === values.sourceObservationId) {
                        return
                    }
                    const similarQuery = readSimilarSearchIntent(similar)
                    if (similarQuery) {
                        actions.searchSimilar(similarQuery, similar)
                    } else {
                        // No stored query: clearing drops the param and the previous results.
                        actions.clearSearch()
                    }
                    return
                }
                // kea-router decodes ?q=true to a boolean, so stringify instead of dropping it.
                const raw = searchParams.q
                const q = typeof raw === 'string' ? raw : raw != null ? String(raw) : ''
                // Run a deep-linked query once. The trimmed-input check blocks the actionToUrl echo and keeps
                // a failed query from re-firing on unrelated URL changes.
                if (q && q !== values.searchedQuery && q !== values.query.trim()) {
                    actions.setQuery(q)
                    actions.search()
                } else if (!q && values.searchedQuery !== null && values.sourceObservationId === null) {
                    // The URL lost its query (back navigation, or a tab switch dropped it), so show the empty state.
                    actions.clearSearch()
                }
            },
        }
    }),
])
