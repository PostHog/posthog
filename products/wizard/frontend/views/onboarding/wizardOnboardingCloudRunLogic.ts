export const wizardOnboardingCloudRunLogic = kea<wizardOnboardingCloudRunLogicType>([
    props({} as WizardOnboardingCloudRunProps),
    key(({ projectId, userId }) => `${projectId}.${userId}`),
    path((key) => ['products', 'wizard', 'wizardOnboardingCloudRunLogic', key]),
    connect((props: WizardOnboardingCloudRunProps) => ({
        values: [
            integrationsLogic,
            ['githubIntegrations', 'integrations', 'integrationsLoading'],
            wizardInstallStepLogic,
            ['cloudRunEnabled'],
            onboardingLogic,
            ['installStepReturnUrl'],
            onboardingWizardRunLogic(props),
            ['run'],
        ],
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        setMode: (mode: 'cloud' | 'local') => ({ mode }),
        setRepository: (repository: string) => ({ repository, idempotencyKey: uuid() }),
        startCloudRun: true,
        retrySetup: true,
    }),
    reducers({
        mode: ['cloud' as 'cloud' | 'local', { setMode: (_, { mode }) => mode }],
        repository: ['', { setRepository: (_, { repository }) => repository }],
        idempotencyKey: [
            () => uuid(),
            {
                setRepository: (_, { idempotencyKey }) => idempotencyKey,
                createRunRequestSuccess: () => uuid(),
            },
        ],
        registryError: [false, { loadRegistry: () => false, loadRegistryFailure: () => true }],
        createError: [
            null as string | null,
            {
                createRunRequest: () => null,
                setRepository: () => null,
                createRunRequestFailure: () => 'Could not start the cloud run. Check the repository and try again.',
            },
        ],
    }),
    loaders(({ props }) => ({
        registry: [
            null as WizardProgramApi[] | null,
            {
                loadRegistry: async () =>
                    (await wizardRegistryList(props.projectId, { limit: 100, offset: 0 })).results,
            },
        ],
        createRunRequest: [
            null as WizardRunApi | null,
            {
                createRunRequest: async (body: WizardRunCreateRequestApi) => wizardRunsCreate(props.projectId, body),
            },
        ],
    })),
    selectors(({ props }) => ({
        githubIntegration: [
            (s) => [s.githubIntegrations],
            (integrations: IntegrationType[]): IntegrationType | null =>
                resolveTeamGitHubIntegration(integrations) ?? null,
        ],
        program: [
            (s) => [s.registry],
            (registry: WizardProgramApi[] | null): WizardProgramApi | null =>
                registry?.find(
                    (program) =>
                        program.id === 'posthog-integration' && program.supported_environments.includes('cloud')
                ) ?? null,
        ],
        setupLoading: [
            (s) => [s.integrationsLoading, s.registryLoading, s.registry, s.registryError],
            (
                integrationsLoading: boolean,
                registryLoading: boolean,
                registry: WizardProgramApi[] | null,
                registryError: boolean
            ): boolean => integrationsLoading || registryLoading || (registry === null && !registryError),
        ],
        setupError: [
            (s) => [s.integrations, s.registryError],
            (integrations: IntegrationType[] | null, registryError: boolean): string | null =>
                !integrations
                    ? 'Could not check the GitHub connection. Retry or run it yourself.'
                    : registryError
                      ? 'Could not load the setup program. Retry or run it yourself.'
                      : null,
        ],
        startLabel: [
            (s) => [s.run],
            (run: WizardRunApi | null): string =>
                run && ['failed', 'cancelled'].includes(run.status) ? 'Retry cloud setup' : 'Install PostHog here',
        ],
        runActive: [(s) => [s.run], (run: WizardRunApi | null): boolean => !!run && wizardRunIsActive(run)],
        connectGitHubUrl: [
            (s) => [s.installStepReturnUrl],
            (returnUrl: string): string =>
                `${getIntegrationsAuthorizeRetrieveUrl(props.projectId)}?${new URLSearchParams({ kind: 'github', next: returnUrl })}`,
        ],
    })),
    listeners(({ actions, values, props }) => ({
        retrySetup: () => {
            if (!values.integrations) {
                actions.loadIntegrations()
            } else {
                actions.loadRegistry()
            }
        },
        setMode: ({ mode }) => {
            posthog.capture('onboarding install mode selected', { mode })
        },
        startCloudRun: () => {
            if (
                !values.cloudRunEnabled ||
                values.runActive ||
                values.createRunRequestLoading ||
                !values.githubIntegration ||
                !values.repository ||
                !values.program
            ) {
                return
            }
            posthog.capture('wizard run create requested', {
                ...wizardEventProperties(props.projectId, 'cloud'),
                location: 'onboarding',
                program_id: values.program.id,
            })
            actions.createRunRequest({
                program_id: values.program.id,
                wizard_version: values.program.wizard_version,
                environment: 'cloud',
                workspace: { type: 'git_repository', repository: values.repository },
                idempotency_key: values.idempotencyKey,
            })
        },
        createRunRequestSuccess: ({ createRunRequest: run }) => {
            const onboarding = onboardingWizardRunLogic(props)
            onboarding.actions.acceptCreatedRun(run)
            wizardRunSyncLogic({ projectId: props.projectId }).actions.runsLoaded([run], true)
        },
        createRunRequestFailure: () => {
            posthog.capture('wizard run create failed', {
                ...wizardEventProperties(props.projectId, 'cloud'),
                location: 'onboarding',
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadIntegrations()
        actions.loadRegistry()
    }),
])
