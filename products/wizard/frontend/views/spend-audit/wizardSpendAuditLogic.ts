export const wizardSpendAuditLogic: LogicWrapper<wizardSpendAuditLogicType> = kea<wizardSpendAuditLogicType>([
    props({} as WizardSpendAuditLogicProps),
    key(({ projectId, userId }) => `${projectId}.${userId}`),
    path((key) => ['products', 'wizard', 'wizardSpendAuditLogic', key]),
    connect(({ projectId }: WizardSpendAuditLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            integrationsLogic,
            ['githubIntegrations', 'integrations', 'integrationsLoading'],
            preflightLogic,
            ['preflight'],
            billingLogic,
            ['accountOwner as billingAccountOwner'],
            organizationLogic,
            ['currentOrganization'],
            wizardRunSyncLogic({ projectId }),
            ['artifactsByRunId', 'runDataErrors', 'runDataLoading', 'tasksByRunId', 'userRuns'],
        ],
        actions: [
            integrationsLogic,
            ['loadIntegrations', 'loadIntegrationsSuccess'],
            wizardRunSyncLogic({ projectId }),
            ['checkRuns', 'loadRunData', 'runsLoaded', 'runUpdated', 'watchRuns'],
        ],
    })),
    actions({
        openModal: (source: WizardSpendAuditOpenSource) => ({ source }),
        closeModal: true,
        setRepository: (repository: string) => ({ repository, idempotencyKey: uuid() }),
        requireRepositoryChoice: true,
        rotateIdempotencyKey: true,
        startAudit: true,
        runAgain: true,
        retrySetup: true,
        syncRun: true,
        trackRun: (runId: string) => ({ runId }),
    }),
    loaders(({ props, values }) => ({
        registry: [
            null as WizardProgramApi[] | null,
            {
                loadRegistry: async () =>
                    (await wizardRegistryList(props.projectId, { limit: 100, offset: 0 })).results,
            },
        ],
        repositories: [
            null as WizardSpendAuditRepositories | null,
            {
                loadRepositories: async (_ = undefined, breakpoint) => {
                    const integration = values.githubIntegration
                    if (!integration) {
                        return null
                    }
                    const response = await api.integrations.githubRepositories(integration.id, {
                        limit: REPOSITORY_PROBE_LIMIT,
                        offset: 0,
                    })
                    await breakpoint()
                    return {
                        repositories: response.repositories.filter(isWizardRepositoryEligible),
                        hasMore: response.has_more,
                    }
                },
            },
        ],
        createRunRequest: [
            null as WizardRunApi | null,
            {
                createRunRequest: async (body: WizardRunCreateRequestApi) => wizardRunsCreate(props.projectId, body),
            },
        ],
    })),
    reducers({
        isModalOpen: [false, { openModal: () => true, closeModal: () => false }],
        // A finished audit stays reachable from the button after the page reloads. Starting another
        // one, from Run again or on the way back from the GitHub install, hides it.
        showLatestFinishedRun: [
            true,
            {
                openModal: (_, { source }) => source !== 'github_return',
                runAgain: () => false,
            },
        ],
        // The click on "Optimize my spend" is the intent to run. It survives the GitHub round trip
        // through the URL param, and it is spent on the first start attempt or when the user has
        // to choose between repositories.
        autoStartPending: [
            false,
            {
                openModal: () => true,
                closeModal: () => false,
                startAudit: () => false,
                requireRepositoryChoice: () => false,
                // Run again from a finished audit waits for a click, so a later repository reload never starts one.
                runAgain: () => false,
            },
        ],
        repository: ['', { setRepository: (_, { repository }) => repository }],
        idempotencyKey: [
            () => uuid(),
            {
                setRepository: (_, { idempotencyKey }) => idempotencyKey,
                createRunRequestSuccess: () => uuid(),
                rotateIdempotencyKey: () => uuid(),
            },
        ],
        registryError: [false, { loadRegistry: () => false, loadRegistryFailure: () => true }],
        // The run the modal follows: one created here, or an in-flight audit picked up on open.
        // Pinning the id keeps a picked-up audit on screen after it finishes.
        trackedRunId: [
            null as string | null,
            {
                createRunRequestSuccess: (_, { createRunRequest }) => createRunRequest.id,
                trackRun: (_, { runId }) => runId,
                runAgain: () => null,
            },
        ],
        createError: [
            null as string | null,
            {
                createRunRequest: () => null,
                setRepository: () => null,
                closeModal: () => null,
                createRunRequestFailure: (_, { errorObject }) =>
                    wizardCreateRunError(errorObject, 'Could not start the audit. Check the repository and try again.'),
            },
        ],
    }),
    selectors(({ props }) => ({
        // Managed accounts have an assigned PostHog contact. The prompt needs both a name and an address.
        accountOwner: [
            (s) => [s.billingAccountOwner],
            (billingAccountOwner: { email?: string; name?: string } | null): WizardSpendAuditAccountOwner | null =>
                billingAccountOwner?.name && billingAccountOwner?.email
                    ? { name: billingAccountOwner.name, email: billingAccountOwner.email }
                    : null,
        ],
        enabled: [
            (s) => [s.featureFlags, s.preflight],
            (flags: FeatureFlagsSet, preflight: PreflightStatus | null): boolean =>
                flags[FEATURE_FLAGS.BILLING_OPTIMIZE_SPEND] === true &&
                !!preflight?.wizard_cloud_run_available &&
                !!(preflight.cloud || preflight.is_debug),
        ],
        githubIntegration: [
            (s) => [s.githubIntegrations],
            (integrations: IntegrationType[]): IntegrationType | null =>
                resolveTeamGitHubIntegration(integrations) ?? null,
        ],
        program: [
            (s) => [s.registry],
            (registry: WizardProgramApi[] | null): WizardProgramApi | null =>
                wizardCloudProgram(registry, WIZARD_SPEND_AUDIT_PROGRAM_ID),
        ],
        setupLoading: [
            (s) => [s.integrationsLoading, s.registryLoading, s.registry, s.registryError],
            (
                integrationsLoading: boolean,
                registryLoading: boolean,
                registry: WizardProgramApi[] | null,
                registryError: boolean
            ): boolean => wizardCloudSetupLoading(integrationsLoading, registryLoading, registry, registryError),
        ],
        setupError: [
            (s) => [s.integrations, s.registryError],
            (integrations: IntegrationType[] | null, registryError: boolean): string | null =>
                wizardCloudSetupError(integrations, registryError, {
                    integrations: 'Could not check the GitHub connection. Try again.',
                    registry: 'Could not load the audit program. Try again.',
                }),
        ],
        singleRepository: [
            (s) => [s.repositories],
            (repositories: WizardSpendAuditRepositories | null): string | null =>
                repositories && !repositories.hasMore && repositories.repositories.length === 1
                    ? repositories.repositories[0].full_name
                    : null,
        ],
        run: [
            (s) => [s.userRuns, s.trackedRunId, s.showLatestFinishedRun],
            (
                userRuns: WizardRunApi[],
                trackedRunId: string | null,
                showLatestFinishedRun: boolean
            ): WizardRunApi | null => {
                if (trackedRunId) {
                    return userRuns.find((run) => run.id === trackedRunId) ?? null
                }
                const audits = userRuns.filter((run) => run.program.id === WIZARD_SPEND_AUDIT_PROGRAM_ID)
                // Without a tracked run, pick up an audit this user already has in flight so a
                // second click never starts a duplicate.
                const active = audits.find(wizardRunIsActive)
                if (active || !showLatestFinishedRun) {
                    return active ?? null
                }
                return audits.reduce<WizardRunApi | null>(
                    (latest, candidate) => (!latest || candidate.created_at > latest.created_at ? candidate : latest),
                    null
                )
            },
        ],
        runActive: [(s) => [s.run], (run: WizardRunApi | null): boolean => !!run && wizardRunIsActive(run)],
        runTasks: [
            (s) => [s.run, s.tasksByRunId],
            (run: WizardRunApi | null, tasksByRunId: Record<string, readonly WizardRunTaskApi[]>) =>
                run ? (tasksByRunId[run.id] ?? []) : [],
        ],
        runArtifacts: [
            (s) => [s.run, s.artifactsByRunId],
            (run: WizardRunApi | null, artifactsByRunId: Record<string, WizardRunArtifactApi[]>) =>
                run ? (artifactsByRunId[run.id] ?? []) : [],
        ],
        runDataIsLoading: [
            (s) => [s.run, s.runDataLoading],
            (run: WizardRunApi | null, runDataLoading: Record<string, boolean>): boolean =>
                run ? (runDataLoading[run.id] ?? true) : false,
        ],
        runDataError: [
            (s) => [s.run, s.runDataErrors],
            (run: WizardRunApi | null, runDataErrors: Record<string, string | null>): string | null =>
                run ? (runDataErrors[run.id] ?? null) : null,
        ],
        view: [
            (s) => [s.setupLoading, s.setupError, s.enabled, s.program, s.githubIntegration, s.run, s.trackedRunId],
            (
                setupLoading: boolean,
                setupError: string | null,
                enabled: boolean,
                program: WizardProgramApi | null,
                githubIntegration: IntegrationType | null,
                run: WizardRunApi | null,
                trackedRunId: string | null
            ): WizardSpendAuditView => {
                // A tracked run stays visible even while the API reloads around it.
                if (run || trackedRunId) {
                    return 'run'
                }
                if (setupLoading) {
                    return 'loading'
                }
                if (setupError) {
                    return 'error'
                }
                if (!enabled || !program) {
                    return 'unavailable'
                }
                if (!githubIntegration) {
                    return 'connect_github'
                }
                return 'pick_repository'
            },
        ],
        connectGitHubUrl: [
            () => [],
            (): string => {
                const next = combineUrl(billingOverviewUrl(), { [WIZARD_SPEND_AUDIT_URL_PARAM]: 'start' }).url
                return `${getIntegrationsAuthorizeRetrieveUrl(props.projectId)}?${new URLSearchParams({ kind: 'github', next })}`
            },
        ],
    })),
    listeners(({ actions, values, props }) => {
        const startIfReady = (): void => {
            if (!values.autoStartPending || values.view !== 'pick_repository' || values.repositoriesLoading) {
                return
            }
            if (values.singleRepository) {
                if (!values.repository) {
                    actions.setRepository(values.singleRepository)
                }
                actions.startAudit()
            } else if (values.repositories) {
                actions.requireRepositoryChoice()
            }
        }

        return {
            openModal: ({ source }) => {
                // pinned: the account owner alert workflow triggers on this event and routes on account_owner_email
                posthog.capture('billing optimize spend opened', {
                    ...wizardEventProperties(props.projectId, 'cloud'),
                    location: SPEND_AUDIT_LOCATION,
                    source,
                    has_account_owner: !!values.accountOwner,
                    account_owner_email: values.accountOwner?.email ?? null,
                    organization_name: values.currentOrganization?.name ?? null,
                })
                actions.loadIntegrations()
                actions.loadRegistry()
                actions.checkRuns(true)
                actions.syncRun()
            },
            retrySetup: () => {
                if (!values.integrations) {
                    actions.loadIntegrations()
                } else {
                    actions.loadRegistry()
                }
            },
            loadIntegrationsSuccess: () => {
                if (values.isModalOpen && values.githubIntegration) {
                    actions.loadRepositories()
                }
            },
            loadRepositoriesSuccess: startIfReady,
            loadRegistrySuccess: startIfReady,
            // A retry of a lost response reuses the key and gets the same run back. A new audit after a
            // finished one needs a fresh key, or the API would return the finished run again.
            runAgain: () => {
                actions.rotateIdempotencyKey()
            },
            startAudit: () => {
                if (
                    !values.enabled ||
                    values.runActive ||
                    values.createRunRequestLoading ||
                    !values.githubIntegration ||
                    !values.repository ||
                    !values.program
                ) {
                    return
                }
                posthog.capture('wizard run create requested', {
                    ...wizardEventProperties(props.projectId, 'cloud'),
                    location: SPEND_AUDIT_LOCATION,
                    program_id: values.program.id,
                })
                actions.createRunRequest(
                    wizardCloudRunRequest(values.program, values.repository, values.idempotencyKey)
                )
            },
            createRunRequestSuccess: ({ createRunRequest: run }) => {
                posthog.capture('wizard run create succeeded', {
                    ...wizardRunEventProperties(run),
                    location: SPEND_AUDIT_LOCATION,
                })
                actions.runsLoaded([run], true)
            },
            // Runs arrive from the list, the stream and the create response, so tasks and artifacts
            // load again whenever the tracked run changes, including its final state.
            runsLoaded: () => actions.syncRun(),
            runUpdated: () => actions.syncRun(),
            syncRun: () => {
                const run = values.run
                if (run && values.isModalOpen && !values.trackedRunId) {
                    actions.trackRun(run.id)
                }
                actions.watchRuns('billing_spend_audit', run && values.isModalOpen ? [run.id] : [])
                if (run) {
                    actions.loadRunData(run)
                }
            },
            createRunRequestFailure: () => {
                posthog.capture('wizard run create failed', {
                    ...wizardEventProperties(props.projectId, 'cloud'),
                    location: SPEND_AUDIT_LOCATION,
                })
            },
            closeModal: () => {
                actions.watchRuns('billing_spend_audit', [])
            },
        }
    }),
    urlToAction(({ actions }) => ({
        [billingOverviewUrl()]: (_, searchParams) => {
            if (searchParams[WIZARD_SPEND_AUDIT_URL_PARAM] !== 'start') {
                return
            }
            // Drop the param right away so a reload or a back navigation does not reopen the flow.
            const { [WIZARD_SPEND_AUDIT_URL_PARAM]: _start, ...rest } = searchParams
            router.actions.replace(billingOverviewUrl(), rest)
            actions.openModal('github_return')
        },
    })),
])
