// The registry program the audit runs. The registry is served by the `wizard-program-registry`
// flag payload, so a program with this id has to exist there before the button can start a run.
export const WIZARD_SPEND_AUDIT_PROGRAM_ID = 'spend-audit'

// pinned: URL search param — the GitHub app install redirects back to the billing page with it
// so the audit continues without another click.
