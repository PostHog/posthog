"""Render the SQL that cohort-seeder uses to read flag calls from flag_evaluations_json.

A renderer in the projection registry (`tools/hogli-commands/hogli_commands/projections.py`). Run
`hogli build:projections --only cohort-seeder-flag-evaluations-json-documents` after a change to the document builder.

The seeder evaluates each row from the JSON text that the legacy flag_evaluations table stores. These expressions
rebuild that text from the columns of a flag_evaluations_json row aliased `e`, under the settings every scan of the
table sends.
"""

import json

from posthog.hogql.printer.events_json_document import event_document_sql, person_document_sql

from posthog.clickhouse.events_json import EVENTS_JSON_READ_SETTINGS, NULL_KEYS_COLUMNS, TEMPORARY_PROPERTIES_COLUMN

OUTPUT = "rust/cohort-seeder/src/clickhouse/flag_evaluations_json_documents.generated.json"


def render() -> dict[str, str]:
    documents = {
        "//": "THIS FILE IS AUTOGENERATED. DO NOT EDIT MANUALLY. To update: hogli build:projections",
        "properties": event_document_sql(
            "e.properties",
            f"e.{TEMPORARY_PROPERTIES_COLUMN}",
            "e.properties.`$feature_flags`",
            null_keys_sqls=(
                f"e.{NULL_KEYS_COLUMNS['properties']}",
                f"e.{NULL_KEYS_COLUMNS[TEMPORARY_PROPERTIES_COLUMN]}",
            ),
        ),
        "person_properties": person_document_sql(
            "e.person_properties", null_keys_sqls=(f"e.{NULL_KEYS_COLUMNS['person_properties']}",)
        ),
        "settings": {name: str(value) for name, value in EVENTS_JSON_READ_SETTINGS.items()},
    }
    return {OUTPUT: json.dumps(documents, indent=4)}
