import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'

import { FEATURE_FLAGS } from 'lib/constants'
import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { removeProjectIdIfPresent, stripTrailingSlash } from 'lib/utils/kea-router'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import type { FeatureFlagsSet } from '../../../../frontend/src/lib/logic/featureFlagLogic'
import type { TeamPublicType, TeamType } from '../../../../frontend/src/types'
import { realtimeCohortsJoinCreate, realtimeCohortsJoinRetrieve } from '../generated/api'
import type { RealtimeCohortsJoinStateEnumApi } from '../generated/api.schemas'

const POLL_INTERVAL_MS = 5000
const JOIN_STATE_POLL = 'joinStatePoll'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface realtimeCohortsJoinLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    currentTeamId: number | null // teamLogic
    joinRequested: boolean
    joinState: RealtimeCohortsJoinStateEnumApi | null
    sawSettingUp: boolean
    shouldJoin: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface realtimeCohortsJoinLogicActions {
    setFeatureFlags: (
        flags: string[],
        variants: Record<string, boolean | string>
    ) => {
        flags: string[]
        variants: Record<string, boolean | string>
    } // featureFlagLogic
    loadCurrentTeam: () => any // teamLogic
    join: () => {
        value: true
    }
    loadJoinState: () => {
        value: true
    }
    setJoinState: (joinState: RealtimeCohortsJoinStateEnumApi) => {
        joinState: RealtimeCohortsJoinStateEnumApi
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface realtimeCohortsJoinLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        shouldJoin: (
            joinRequested: boolean,
            currentTeam: TeamPublicType | TeamType | null,
            featureFlags: FeatureFlagsSet
        ) => boolean
    }
}

export type realtimeCohortsJoinLogicType = MakeLogicType<
    realtimeCohortsJoinLogicValues,
    realtimeCohortsJoinLogicActions,
    Record<string, any>,
    realtimeCohortsJoinLogicMeta
>

export const realtimeCohortsJoinLogic = kea<realtimeCohortsJoinLogicType>([
    path(['products', 'cohorts', 'frontend', 'realtime', 'realtimeCohortsJoinLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentTeamId'], featureFlagLogic, ['featureFlags']],
        actions: [teamLogic, ['loadCurrentTeam'], featureFlagLogic, ['setFeatureFlags']],
    })),
    actions({
        join: true,
        loadJoinState: true,
        setJoinState: (joinState: RealtimeCohortsJoinStateEnumApi) => ({ joinState }),
    }),
    reducers({
        joinState: [null as RealtimeCohortsJoinStateEnumApi | null, { setJoinState: (_, { joinState }) => joinState }],
        // A project that cannot join gets one request per page load, not one per flag reload.
        joinRequested: [false, { join: () => true }],
        sawSettingUp: [
            false,
            { setJoinState: (sawSettingUp, { joinState }) => sawSettingUp || joinState === 'setting_up' },
        ],
    }),
    selectors({
        // posthog-js turns the flag on in this browser at the opt-in itself, so this one condition covers the opt-in
        // and every later visit of a person who opted in.
        shouldJoin: [
            (s) => [s.joinRequested, s.currentTeam, s.featureFlags],
            (
                joinRequested: boolean,
                currentTeam: TeamPublicType | TeamType | null,
                featureFlags: FeatureFlagsSet
            ): boolean =>
                !joinRequested &&
                !window.IMPERSONATED_SESSION &&
                currentTeam?.realtime_cohorts?.access === 'off' &&
                !!featureFlags[FEATURE_FLAGS.REALTIME_COHORTS],
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setFeatureFlags: () => {
            if (values.shouldJoin) {
                actions.join()
            }
        },
        join: async () => {
            try {
                actions.setJoinState((await realtimeCohortsJoinCreate(String(values.currentTeamId))).state)
            } catch {
                // Nobody asked for this request, so a failure shows nothing. The next page load asks again.
            }
        },
        loadJoinState: async () => {
            try {
                actions.setJoinState((await realtimeCohortsJoinRetrieve(String(values.currentTeamId))).state)
            } catch {
                // Only a `setting_up` answer arms the next read, so a failed read arms it in the answer's place.
                actions.setJoinState('setting_up')
            }
        },
        setJoinState: ({ joinState }) => {
            if (joinState === 'setting_up') {
                // Each answer arms one read, so reads never overlap and a slow answer cannot land after a newer one.
                cache.disposables.add(() => {
                    const pollTimer = window.setTimeout(() => actions.loadJoinState(), POLL_INTERVAL_MS)
                    return () => clearTimeout(pollTimer)
                }, JOIN_STATE_POLL)
                return
            }
            cache.disposables.dispose(JOIN_STATE_POLL)
            if (joinState === 'serving') {
                // Every realtime cohorts screen reads the team's access, so they all switch with the reload.
                actions.loadCurrentTeam()
                if (values.sawSettingUp) {
                    const onCohortsList =
                        stripTrailingSlash(removeProjectIdIfPresent(router.values.location.pathname)) === urls.cohorts()
                    lemonToast.success(
                        'Realtime cohorts are on for this project. Open a cohort and turn on realtime so feature flags can target it.',
                        {
                            button: onCohortsList
                                ? undefined
                                : {
                                      label: 'View cohorts',
                                      action: () => router.actions.push(urls.cohorts()),
                                      // Autocapture insights find the click by this data-attr, so keep it unchanged.
                                      dataAttr: 'realtime-cohorts-joined-view-cohorts',
                                  },
                        }
                    )
                }
            }
        },
    })),
    // The flags and the team usually arrive before this logic mounts, so it checks once on mount too.
    afterMount(({ actions, values }) => {
        if (values.shouldJoin) {
            actions.join()
        }
    }),
])
