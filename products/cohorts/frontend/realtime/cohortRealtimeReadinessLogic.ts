export const cohortRealtimeReadinessLogic: LogicWrapper<cohortRealtimeReadinessLogicType> =
    kea<cohortRealtimeReadinessLogicType>([
        props({} as CohortRealtimeReadinessLogicProps),
        key(({ cohortId }) => cohortId),
        path((key) => ['products', 'cohorts', 'frontend', 'realtime', 'cohortRealtimeReadinessLogic', key]),
        connect(() => ({
            values: [teamLogic, ['currentProjectId'], cohortsModel, ['cohortsById']],
            actions: [teamLogic, ['refreshCurrentTeam'], cohortsModel, ['updateCohort']],
        })),
        actions({
            refreshReadiness: true,
            armReadinessPoll: true,
        }),
        loaders(({ props, values }) => ({
            realtimeSwitch: [
                null as CohortApi | null,
                {
                    turnOnRealtime: async () =>
                        await cohortsRealtimeCreate(String(values.currentProjectId), props.cohortId, { enabled: true }),
                },
            ],
        })),
        selectors({
            cohort: [
                (s, p) => [s.cohortsById, p.cohortId],
                (cohortsById: Partial<Record<number | string, CohortType>>, cohortId: number): CohortType | undefined =>
                    cohortsById[cohortId],
            ],
        }),
        listeners(({ actions, values, props, cache }) => {
            // Only the readiness merges back, so the rest of the list's basic payload that other readers of the shared
            // model use stays as it was. The API sends no readiness when its lookup of queued builds fails. That says
            // nothing about the build, so the last known state stays rather than reading as a cohort flags can target.
            const mergeReadiness = (fetched: CohortApi): void => {
                if (values.cohort && fetched.realtime) {
                    actions.updateCohort({
                        ...values.cohort,
                        realtime_enabled: fetched.realtime_enabled,
                        realtime: fetched.realtime,
                    })
                }
            }

            return {
                turnOnRealtimeSuccess: ({ realtimeSwitch }) => {
                    mergeReadiness(realtimeSwitch)
                    cache.readinessGeneration = (cache.readinessGeneration ?? 0) + 1
                    actions.armReadinessPoll()
                    // The usage line reads `cohorts_used` from the current team, and turning one cohort on can turn on
                    // the cohorts it includes.
                    actions.refreshCurrentTeam()
                },
                // A refusal at the plan's limit can come from usage that changed since the team loaded.
                turnOnRealtimeFailure: () => {
                    actions.refreshCurrentTeam()
                },
                refreshReadiness: async (_, breakpoint) => {
                    // A turn-on lands a fresher readiness than a request already in flight, so a response that
                    // crosses one is dropped. `breakpoint()` cannot catch that, because a turn-on never dispatches
                    // this action.
                    const generation = cache.readinessGeneration
                    let fetched: CohortApi | null = null
                    try {
                        fetched = await cohortsRetrieve(String(values.currentProjectId), props.cohortId)
                    } catch {
                        // Keep watching: a failed request says nothing about the build.
                    }
                    breakpoint()
                    if (generation !== cache.readinessGeneration) {
                        return
                    }
                    if (fetched) {
                        mergeReadiness(fetched)
                        // Only a build this logic watched is news. A cohort the shared model still shows as preparing
                        // may have been ready for an hour.
                        if (cache.watchedBuild && fetched.realtime?.state === 'ready') {
                            cache.watchedBuild = false
                            lemonToast.success(`Cohort '${fetched.name}' is ready. Feature flags can target it now.`)
                        }
                    }
                    actions.armReadinessPoll()
                },
                armReadinessPoll: () => {
                    if (isBuildingHistory(values.cohort)) {
                        cache.watchedBuild = true
                        cache.readinessGracePolls = READINESS_GRACE_POLLS
                    } else if (values.cohort?.realtime?.state === 'needs_attention' && cache.readinessGracePolls > 0) {
                        cache.readinessGracePolls -= 1
                    } else {
                        // Disposing rather than just returning. The manager re-runs a registered setup every time the
                        // tab comes back, so a poll left on it would refetch the cohort after each return.
                        cache.disposables.dispose('readinessPoll')
                        return
                    }
                    cache.disposables.add(() => {
                        const timeoutId = window.setTimeout(() => actions.refreshReadiness(), REALTIME_POLL_INTERVAL_MS)
                        return () => window.clearTimeout(timeoutId)
                    }, 'readinessPoll')
                },
            }
        }),
        // The shared model loads its cohorts once per session, so the state it holds can predate a teammate turning
        // the cohort on, or an edit made in the cohort's own tab. The manager runs this setup now, and again each time
        // the tab comes back. Only a cohort the flag can't target yet mounts this logic, so a ready cohort costs no
        // request.
        afterMount(({ actions, values, cache }) => {
            // The first read can land in the gap where a healthy build reads as `needs_attention`, so a cohort the
            // shared model shows as preparing starts with the grace period a build seen by this logic gets.
            if (isBuildingHistory(values.cohort)) {
                cache.readinessGracePolls = READINESS_GRACE_POLLS
            }
            cache.disposables.add(() => {
                actions.refreshReadiness()
                return () => {}
            })
        }),
    ])
