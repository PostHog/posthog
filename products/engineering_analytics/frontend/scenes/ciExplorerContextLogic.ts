/** The Context tab's data. It asks for nothing until the tab is open, and one request at a time after that. */
export const ciExplorerContextLogic = kea<ciExplorerContextLogicType>([
    path(['products', 'engineering_analytics', 'frontend', 'scenes', 'ciExplorerContextLogic']),
    props({} as CIExplorerLogicProps),
    key((props) => `${props.repoOwner}/${props.repoName}#${props.number}@${props.sourceId ?? ''}`),
    connect((props: CIExplorerLogicProps) => ({
        values: [ciExplorerLogic(props), ['workflows', 'focusedNodeId', 'drawerOpen', 'drawerTab', 'view']],
        actions: [
            ciExplorerLogic(props),
            ['setFocus', 'setLocation', 'setView', 'openDrawer', 'closeDrawer', 'loadJobsSuccess'],
        ],
    })),

    actions({
        selectStep: (stepNumber: number | null) => ({ stepNumber }),
        // Null when the pointer leaves the step it was on.
        hoverStep: (stepNumber: number | null) => ({ stepNumber }),
        retry: true,
        sync: true,
    }),

    loaders(({ props, values, cache }) => ({
        answer: [
            null as CIContextAnswer | null,
            {
                loadAnswer: async (selection: CIContextSelection, breakpoint): Promise<CIContextAnswer | null> => {
                    const answers: Map<string, KeptAnswer> = (cache.answers ??= new Map())
                    const kept = answers.get(selection.key)
                    if (kept && kept.expires > Date.now()) {
                        return { key: selection.key, context: kept.context }
                    }
                    await breakpoint(SETTLE_MS)
                    const controller = new AbortController()
                    cache.controller = controller
                    try {
                        const context = await engineeringAnalyticsCiTimingContext(
                            projectId(),
                            {
                                repo: `${props.repoOwner}/${props.repoName}`,
                                source_id: props.sourceId ?? undefined,
                                ci_engine: selection.engine,
                                run_id: selection.runId,
                                run_attempt: selection.runAttempt,
                                kind: selection.kind,
                                job_ids: selection.jobIds.length ? selection.jobIds.join(',') : undefined,
                                step_number: selection.stepNumber ?? undefined,
                            },
                            { signal: controller.signal }
                        )
                        breakpoint()
                        if (answers.size >= ANSWERS_KEPT) {
                            answers.delete(answers.keys().next().value as string)
                        }
                        answers.set(selection.key, { expires: Date.now() + ANSWER_TTL_MS, context })
                        return { key: selection.key, context }
                    } catch (error) {
                        // A cancelled request is not a failure. The tab was closed, or a newer selection replaced it.
                        if (controller.signal.aborted) {
                            breakpoint()
                            return values.answer
                        }
                        throw error
                    }
                },
            },
        ],
    })),

    reducers({
        stepNumber: [
            null as number | null,
            {
                selectStep: (_, { stepNumber }) => stepNumber,
                setFocus: () => null,
                setLocation: () => null,
            },
        ],
        failed: [
            false,
            {
                loadAnswer: () => false,
                loadAnswerFailure: () => true,
            },
        ],
    }),

    selectors({
        active: [
            (s) => [s.drawerOpen, s.drawerTab, s.view],
            (drawerOpen: boolean, drawerTab: CIExplorerDrawerTab, view: CIExplorerView): boolean =>
                drawerOpen && drawerTab === 'context' && view === 'overview',
        ],
        selection: [
            (s) => [s.workflows, s.focusedNodeId, s.stepNumber],
            (
                workflows: CIExplorerWorkflow[],
                focusedNodeId: string | null,
                stepNumber: number | null
            ): CIContextSelection | null => contextSelection(workflows, focusedNodeId, stepNumber),
        ],
        // Null while the answer on hand describes another selection.
        context: [
            (s) => [s.answer, s.selection],
            (answer: CIContextAnswer | null, selection: CIContextSelection | null): CITimingContextApi | null =>
                answer && selection && answer.key === selection.key ? answer.context : null,
        ],
    }),

    listeners(({ actions, values, cache }) => {
        const ask = (): void => {
            cache.controller?.abort()
            if (values.active && values.selection) {
                actions.loadAnswer(values.selection)
            }
        }
        return {
            sync: ask,
            openDrawer: ask,
            closeDrawer: ask,
            setView: ask,
            setFocus: ask,
            setLocation: ask,
            selectStep: ask,
            // A selection restored from a link has nothing to compare until its jobs arrive.
            loadJobsSuccess: () => {
                if (values.active && values.selection && values.context === null && !values.answerLoading) {
                    ask()
                }
            },
            hoverStep: async ({ stepNumber }, breakpoint) => {
                // The wait ends early when the pointer moves to another step or leaves, so only a rest selects.
                await breakpoint(STEP_HOVER_MS)
                if (stepNumber !== null && values.active && values.stepNumber !== stepNumber) {
                    actions.selectStep(stepNumber)
                }
            },
            loadAnswerSuccess: ({ answer, payload }) => {
                // A cancelled request hands back the earlier answer, which was counted when it arrived.
                if (answer && payload && answer.key === payload.key) {
                    posthog.capture(EVENT_LOADED, {
                        kind: payload.kind,
                        engine: payload.engine,
                        sample_count: answer.context.sample_count,
                        unavailable_reason: answer.context.unavailable_reason,
                    })
                }
            },
            loadAnswerFailure: () => {
                posthog.capture(EVENT_FAILED, { kind: values.selection?.kind })
            },
            retry: () => {
                if (values.selection) {
                    cache.answers?.delete(values.selection.key)
                }
                ask()
            },
        }
    }),

    // The drawer can mount with the tab already open and a selection already made.
    afterMount(({ actions }) => {
        actions.sync()
    }),

    beforeUnmount(({ cache }) => {
        cache.controller?.abort()
    }),
])
