const projectId = (): string => String(ApiConfig.getCurrentProjectId())

// The server keeps an answer for the same time, so asking again sooner returns the same numbers.
const ANSWER_TTL_MS = 5 * 60 * 1000
const ANSWERS_KEPT = 24
// A pass over several nodes on the way to one asks for the last node only.
const SETTLE_MS = 150
const STEP_HOVER_MS = 600
// pinned: analytics event names. Renaming one breaks the insights built on it.
const EVENT_LOADED = 'ci explorer timing context loaded'
const EVENT_FAILED = 'ci explorer timing context failed'

/** An answer and the selection it describes. The pair is what keeps a late answer off a newer selection. */
export interface CIContextAnswer {
    key: string
    context: CITimingContextApi
}

interface KeptAnswer {
    expires: number
    context: CITimingContextApi
}

