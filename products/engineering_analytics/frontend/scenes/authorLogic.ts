import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { ApiConfig } from 'lib/api'

import { Breadcrumb } from '~/types'

import { engineeringAnalyticsAuthorFrictionDetail, engineeringAnalyticsAuthorWorkflowCosts } from '../generated/api'
import type { AuthorFrictionDetailApi, WorkflowCostApi } from '../generated/api.schemas'
import { DeliveryScope } from '../lib/deliveryScope'
import { repoBreadcrumbs } from '../lib/repoBreadcrumbs'
import { engineeringAnalyticsFiltersLogic } from './engineeringAnalyticsFiltersLogic'

export interface AuthorLogicProps {
    handle: string
    // Which GitHub source the page was scoped to, threaded from `?source=` via paramsToProps.
    sourceId: string | null
    /** The 'owner/name' from the path. Every figure on the page is this repository's. */
    repo: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface authorLogicValues {
    dateFrom: string | null // engineeringAnalyticsFiltersLogic
    dateTo: string | null // engineeringAnalyticsFiltersLogic
    breadcrumbs: Breadcrumb[]
    deliveryScope: DeliveryScope
    frictionDetail: AuthorFrictionDetailApi | null
    frictionDetailFailed: boolean
    frictionDetailLoading: boolean
    handle: string
    repo: string | null
    sourceId: string | null
    workflowCosts: WorkflowCostApi[]
    workflowCostsFailed: boolean
    workflowCostsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface authorLogicActions {
    loadFrictionDetail: () => any
    loadFrictionDetailFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFrictionDetailSuccess: (
        frictionDetail: AuthorFrictionDetailApi,
        payload?: any
    ) => {
        frictionDetail: AuthorFrictionDetailApi
        payload?: any
    }
    loadWorkflowCosts: () => any
    loadWorkflowCostsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadWorkflowCostsSuccess: (
        workflowCosts: WorkflowCostApi[],
        payload?: any
    ) => {
        workflowCosts: WorkflowCostApi[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface authorLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        sourceId: (arg: string | null) => string | null
        repo: (arg: string | null) => string | null
        handle: (arg: string) => string
        deliveryScope: (handle: string) => DeliveryScope
        breadcrumbs: (repo: string | null, sourceId: string | null, searchParams: Record<string, any>) => Breadcrumb[]
    }
}

export type authorLogicType = MakeLogicType<authorLogicValues, authorLogicActions, AuthorLogicProps, authorLogicMeta>

export const authorLogic = kea<authorLogicType>([
    path(['products', 'engineering_analytics', 'frontend', 'scenes', 'authorLogic']),
    props({} as AuthorLogicProps),
    key((props) => `author/${props.handle}@${props.repo ?? ''}@${props.sourceId ?? ''}`),

    connect(() => ({
        values: [engineeringAnalyticsFiltersLogic, ['dateFrom', 'dateTo']],
    })),

    loaders(({ props, values }) => ({
        // The author's CI spend split by workflow, for "where their CI minutes go". [] when the
        // job-level source isn't synced.
        workflowCosts: [
            [] as WorkflowCostApi[],
            {
                loadWorkflowCosts: async () =>
                    await engineeringAnalyticsAuthorWorkflowCosts(String(ApiConfig.getCurrentProjectId()), {
                        author: props.handle,
                        date_from: values.dateFrom ?? undefined,
                        date_to: values.dateTo ?? undefined,
                        source_id: props.sourceId ?? undefined,
                        repo: props.repo ?? undefined,
                    }),
            },
        ],
        // A fixed 30-day window from the materialized friction view, so the date picker does not move it.
        frictionDetail: [
            null as AuthorFrictionDetailApi | null,
            {
                loadFrictionDetail: async () =>
                    await engineeringAnalyticsAuthorFrictionDetail(String(ApiConfig.getCurrentProjectId()), {
                        author: props.handle,
                        source_id: props.sourceId ?? undefined,
                        repo: props.repo ?? undefined,
                    }),
            },
        ],
    })),

    reducers({
        workflowCostsFailed: [false, { loadWorkflowCosts: () => false, loadWorkflowCostsFailure: () => true }],
        frictionDetailFailed: [false, { loadFrictionDetail: () => false, loadFrictionDetailFailure: () => true }],
    }),

    listeners(({ actions }) => ({
        [engineeringAnalyticsFiltersLogic.actionTypes.setDateRange]: () => {
            actions.loadWorkflowCosts()
        },
    })),

    selectors({
        sourceId: [
            () => [(_, p: AuthorLogicProps) => p.sourceId],
            (sourceId: string | null): string | null => sourceId,
        ],
        repo: [() => [(_, p: AuthorLogicProps) => p.repo], (repo: string | null): string | null => repo],
        handle: [() => [(_, p: AuthorLogicProps) => p.handle], (handle: string): string => handle],
        // Memoized, so the delivery logics keyed by this scope see one stable object per author.
        deliveryScope: [(s) => [s.handle], (handle: string): DeliveryScope => ({ kind: 'author', author: handle })],
        breadcrumbs: [
            (s) => [s.repo, s.sourceId, router.selectors.searchParams],
            (
                repo: string | null,
                sourceId: string | null,
                searchParams: Record<string, string | undefined>
            ): Breadcrumb[] => repoBreadcrumbs(repo, searchParams, sourceId),
        ],
    }),

    afterMount(({ actions }) => {
        actions.loadWorkflowCosts()
        actions.loadFrictionDetail()
    }),
])
