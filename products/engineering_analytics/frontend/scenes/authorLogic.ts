import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiConfig } from 'lib/api'
import { urls } from 'scenes/urls'

import { Breadcrumb } from '~/types'

import {
    engineeringAnalyticsAuthorPullRequestTimelines,
    engineeringAnalyticsAuthorSummary,
    engineeringAnalyticsAuthorWorkflowCosts,
} from '../generated/api'
import type { AuthorPullRequestTimelinesApi, AuthorSummaryApi, WorkflowCostApi } from '../generated/api.schemas'
import {
    DayViewAlignment,
    DayViewGroup,
    RedTimeByCause,
    axisDays,
    groupTimelines,
    redTimeByCause,
} from '../lib/pullRequestDayView'
import { engineeringAnalyticsFiltersLogic } from './engineeringAnalyticsFiltersLogic'

const projectId = (): string => String(ApiConfig.getCurrentProjectId())

export interface AuthorLogicProps {
    handle: string
    // Which GitHub source the page was scoped to, threaded from `?source=` via paramsToProps.
    sourceId: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface authorLogicValues {
    dateFrom: string | null // engineeringAnalyticsFiltersLogic
    dateTo: string | null // engineeringAnalyticsFiltersLogic
    avatarUrl: string
    breadcrumbs: Breadcrumb[]
    dayViewAlignment: DayViewAlignment
    dayViewAxisDays: number
    dayViewGroups: DayViewGroup[]
    handle: string
    loadFailed: boolean
    redTime: RedTimeByCause
    repoSlugs: string[]
    sourceId: string | null
    summary: AuthorSummaryApi | null
    summaryLoading: boolean
    timelines: AuthorPullRequestTimelinesApi | null
    timelinesLoading: boolean
    workflowCosts: WorkflowCostApi[]
    workflowCostsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface authorLogicActions {
    loadSummary: () => any
    loadSummaryFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadSummarySuccess: (
        summary: AuthorSummaryApi | null,
        payload?: any
    ) => { summary: AuthorSummaryApi | null; payload?: any }
    loadTimelines: () => any
    loadTimelinesFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadTimelinesSuccess: (
        timelines: AuthorPullRequestTimelinesApi | null,
        payload?: any
    ) => { timelines: AuthorPullRequestTimelinesApi | null; payload?: any }
    loadWorkflowCosts: () => any
    loadWorkflowCostsFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadWorkflowCostsSuccess: (
        workflowCosts: WorkflowCostApi[],
        payload?: any
    ) => { workflowCosts: WorkflowCostApi[]; payload?: any }
    setDayViewAlignment: (alignment: DayViewAlignment) => { alignment: DayViewAlignment }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface authorLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        sourceId: (arg: string | null) => string | null
        handle: (arg: string) => string
        dayViewGroups: (timelines: AuthorPullRequestTimelinesApi | null) => DayViewGroup[]
        dayViewAxisDays: (timelines: AuthorPullRequestTimelinesApi | null, dayViewAlignment: DayViewAlignment) => number
        redTime: (timelines: AuthorPullRequestTimelinesApi | null) => RedTimeByCause
        avatarUrl: (timelines: AuthorPullRequestTimelinesApi | null) => string
        repoSlugs: (timelines: AuthorPullRequestTimelinesApi | null) => string[]
        breadcrumbs: (handle: string) => Breadcrumb[]
    }
}

export type authorLogicType = MakeLogicType<authorLogicValues, authorLogicActions, AuthorLogicProps, authorLogicMeta>

export const authorLogic = kea<authorLogicType>([
    path(['products', 'engineering_analytics', 'frontend', 'scenes', 'authorLogic']),
    props({} as AuthorLogicProps),
    key((props) => `author/${props.handle}@${props.sourceId ?? ''}`),

    // Every read on the page is windowed by the shared CI-analytics window.
    connect(() => ({
        values: [engineeringAnalyticsFiltersLogic, ['dateFrom', 'dateTo']],
    })),

    actions({
        setDayViewAlignment: (alignment: DayViewAlignment) => ({ alignment }),
    }),

    loaders(({ props, values }) => {
        const params = (): { author: string; date_from?: string; date_to?: string; source_id?: string } => ({
            author: props.handle,
            date_from: values.dateFrom ?? undefined,
            date_to: values.dateTo ?? undefined,
            source_id: props.sourceId ?? undefined,
        })
        return {
            summary: [
                null as AuthorSummaryApi | null,
                { loadSummary: async () => await engineeringAnalyticsAuthorSummary(projectId(), params()) },
            ],
            timelines: [
                null as AuthorPullRequestTimelinesApi | null,
                {
                    loadTimelines: async () =>
                        await engineeringAnalyticsAuthorPullRequestTimelines(projectId(), params()),
                },
            ],
            // The author's CI spend split by workflow, for "where their CI minutes go". [] when the job-level
            // source isn't synced.
            workflowCosts: [
                [] as WorkflowCostApi[],
                { loadWorkflowCosts: async () => await engineeringAnalyticsAuthorWorkflowCosts(projectId(), params()) },
            ],
        }
    }),

    reducers({
        dayViewAlignment: ['days' as DayViewAlignment, { setDayViewAlignment: (_, { alignment }) => alignment }],
        loadFailed: [
            false,
            {
                loadSummary: () => false,
                loadTimelines: () => false,
                loadSummaryFailure: () => true,
                loadTimelinesFailure: () => true,
            },
        ],
    }),

    listeners(({ actions }) => ({
        [engineeringAnalyticsFiltersLogic.actionTypes.setDateRange]: () => {
            actions.loadSummary()
            actions.loadTimelines()
            actions.loadWorkflowCosts()
        },
    })),

    selectors({
        sourceId: [
            () => [(_, p: AuthorLogicProps) => p.sourceId],
            (sourceId: string | null): string | null => sourceId,
        ],
        handle: [() => [(_, p: AuthorLogicProps) => p.handle], (handle: string): string => handle],
        dayViewGroups: [
            (s) => [s.timelines],
            (timelines: AuthorPullRequestTimelinesApi | null): DayViewGroup[] => groupTimelines(timelines?.items ?? []),
        ],
        dayViewAxisDays: [
            (s) => [s.timelines, s.dayViewAlignment],
            (timelines: AuthorPullRequestTimelinesApi | null, alignment: DayViewAlignment): number =>
                axisDays(timelines?.items ?? [], alignment),
        ],
        redTime: [
            (s) => [s.timelines],
            (timelines: AuthorPullRequestTimelinesApi | null): RedTimeByCause => redTimeByCause(timelines?.items ?? []),
        ],
        avatarUrl: [
            (s) => [s.timelines],
            (timelines: AuthorPullRequestTimelinesApi | null): string => timelines?.author_avatar_url ?? '',
        ],
        // A source can hold several repos, so the author's PRs may span repos.
        repoSlugs: [
            (s) => [s.timelines],
            (timelines: AuthorPullRequestTimelinesApi | null): string[] =>
                Array.from(new Set((timelines?.items ?? []).map((pr) => `${pr.repo.owner}/${pr.repo.name}`))),
        ],
        breadcrumbs: [
            (_, p) => [p.handle],
            (handle: string): Breadcrumb[] => [
                {
                    key: 'EngineeringAnalytics',
                    name: 'Engineering analytics',
                    path: urls.engineeringAnalytics(),
                    iconType: 'health',
                },
                {
                    key: 'EngineeringAnalyticsPullRequests',
                    name: 'Pull requests',
                    path: urls.engineeringAnalyticsPullRequestList(),
                    iconType: 'health',
                },
                { key: ['EngineeringAnalyticsAuthor', handle], name: handle, iconType: 'health' },
            ],
        ],
    }),

    afterMount(({ actions }) => {
        actions.loadSummary()
        actions.loadTimelines()
        actions.loadWorkflowCosts()
    }),
])
