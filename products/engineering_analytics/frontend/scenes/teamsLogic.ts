export type teamsLogicType = MakeLogicType<teamsLogicValues, teamsLogicActions, Record<string, any>, teamsLogicMeta>

export const teamsLogic = kea<teamsLogicType>([
    path(['products', 'engineering_analytics', 'frontend', 'scenes', 'teamsLogic']),
    connect(() => ({
        values: [engineeringAnalyticsLogic, ['sourceId']],
        actions: [engineeringAnalyticsLogic, ['setSourceId']],
    })),
    loaders(({ values }) => ({
        teams: [
            null as TeamsData | null,
            {
                loadTeams: async (): Promise<TeamsData> => {
                    const data = await engineeringAnalyticsTeamCiHealth(projectId(), {
                        date_from: DEFAULT_TEAMS_WINDOW,
                        source_id: values.sourceId ?? undefined,
                    })
                    return {
                        rows: data.items.map(toTeamCIHealthRow),
                        truncated: data.truncated,
                        limit: data.limit,
                    }
                },
            },
        ],
    })),
    reducers({
        teamsStatus: [
            'ok' as LoaderStatus,
            {
                loadTeams: () => 'ok',
                loadTeamsSuccess: () => 'ok',
                loadTeamsFailure: (_, { errorObject }) => loaderStatusFromError(errorObject),
            },
        ],
    }),
    selectors({
        teamsFailed: [(s) => [s.teamsStatus], (status: LoaderStatus): boolean => status === 'error'],
        teamsNotConnected: [(s) => [s.teamsStatus], (status: LoaderStatus): boolean => status === 'notConnected'],
    }),
    listeners(({ actions }) => ({
        setSourceId: () => actions.loadTeams(),
    })),
    afterMount(({ actions }) => {
        actions.loadTeams()
    }),
])
