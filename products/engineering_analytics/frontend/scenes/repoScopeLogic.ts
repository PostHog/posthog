// Keeps the repository in the URL: forwards a repo-less product URL (old links, the product root) to a
// repository, and remembers the last repository used per project so the root reopens it.

import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router, urlToAction } from 'kea-router'

import { ApiConfig } from 'lib/api'
import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { teamLogic } from 'scenes/teamLogic'

import { engineeringAnalyticsSources } from '../generated/api'
import type { GitHubSourceApi } from '../generated/api.schemas'
import { pickForwardRepo, repoFromPath, repoPathFor } from '../lib/repoScope'

const projectId = (): string => String(ApiConfig.getCurrentProjectId())

// The repo-less paths that forward. A repo path never forwards.
const LEGACY_PATHS = [
    '/engineering-analytics/overview',
    '/engineering-analytics/pull-requests',
    '/engineering-analytics/workflows',
    '/engineering-analytics/tests',
    '/engineering-analytics/deploys',
    '/engineering-analytics/teams',
    '/engineering-analytics/authors',
    '/engineering-analytics/teams/:ownerTeam',
    '/engineering-analytics/authors/:handle',
]
const REPO_PATHS = [
    '/engineering-analytics/repos/:repoOwner/:repoName/overview',
    '/engineering-analytics/repos/:repoOwner/:repoName/pull-requests',
    '/engineering-analytics/repos/:repoOwner/:repoName/workflows',
    '/engineering-analytics/repos/:repoOwner/:repoName/tests',
    '/engineering-analytics/repos/:repoOwner/:repoName/deploys',
    '/engineering-analytics/repos/:repoOwner/:repoName/teams',
    '/engineering-analytics/repos/:repoOwner/:repoName/authors',
    '/engineering-analytics/repos/:repoOwner/:repoName/teams/:ownerTeam',
    '/engineering-analytics/repos/:repoOwner/:repoName/authors/:handle',
    '/engineering-analytics/repos/:repoOwner/:repoName/pull-requests/:number',
    '/engineering-analytics/repos/:repoOwner/:repoName/pull-requests/:number/ci-explorer',
    '/engineering-analytics/repos/:repoOwner/:repoName/actions/runs/:runId',
    '/engineering-analytics/repos/:repoOwner/:repoName/actions/workflows/:workflowName',
]

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface repoScopeLogicValues {
    currentTeamId: number | null // teamLogic
    githubSources: GitHubSourceApi[] | null
    githubSourcesLoading: boolean
    lastRepo: string | null
    lastRepoByTeam: Record<string, string>
    pendingForward: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface repoScopeLogicActions {
    clearPendingForward: () => {
        value: true
    }
    forwardToRepo: () => {
        value: true
    }
    loadGithubSources: () => any
    loadGithubSourcesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadGithubSourcesSuccess: (
        githubSources: GitHubSourceApi[],
        payload?: any
    ) => {
        githubSources: GitHubSourceApi[]
        payload?: any
    }
    noRepoToForward: () => {
        value: true
    }
    rememberRepo: (
        teamId: number,
        repo: string
    ) => {
        repo: string
        teamId: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface repoScopeLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        lastRepo: (lastRepoByTeam: Record<string, string>, currentTeamId: number | null) => string | null
    }
}

export type repoScopeLogicType = MakeLogicType<
    repoScopeLogicValues,
    repoScopeLogicActions,
    Record<string, any>,
    repoScopeLogicMeta
>

export const repoScopeLogic = kea<repoScopeLogicType>([
    path(['products', 'engineering_analytics', 'frontend', 'scenes', 'repoScopeLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    actions({
        forwardToRepo: true,
        clearPendingForward: true,
        // Nothing to forward to: the repo-less page stays and loads its own connect or empty state.
        noRepoToForward: true,
        rememberRepo: (teamId: number, repo: string) => ({ teamId, repo }),
    }),

    loaders({
        githubSources: [
            null as GitHubSourceApi[] | null,
            {
                loadGithubSources: async (): Promise<GitHubSourceApi[]> =>
                    await engineeringAnalyticsSources(projectId()),
            },
        ],
    }),

    reducers({
        lastRepoByTeam: [
            {} as Record<string, string>,
            { persist: true, prefix: 'engineering_analytics_' },
            { rememberRepo: (state, { teamId, repo }) => ({ ...state, [teamId]: repo }) },
        ],
        // A forward asked for before the repository list loaded waits for it.
        pendingForward: [false, { forwardToRepo: () => true, clearPendingForward: () => false }],
    }),

    selectors({
        lastRepo: [
            (s) => [s.lastRepoByTeam, s.currentTeamId],
            (lastRepoByTeam: Record<string, string>, currentTeamId: number | null): string | null =>
                currentTeamId ? (lastRepoByTeam[currentTeamId] ?? null) : null,
        ],
    }),

    listeners(({ actions, values }) => {
        const forward = (): void => {
            actions.clearPendingForward()
            const pathname = removeProjectIdIfPresent(router.values.location.pathname)
            // The person may have moved on while the repository list loaded.
            if (!pathname.startsWith('/engineering-analytics/') || repoFromPath(pathname)) {
                return
            }
            const { repo, source, ...searchParams } = router.values.searchParams
            const target = pickForwardRepo(values.githubSources ?? [], { repo, sourceId: source }, values.lastRepo)
            // Nothing connected, or only a legacy source with no repository name.
            if (!target) {
                actions.noRepoToForward()
                return
            }
            router.actions.replace(
                repoPathFor(pathname, target),
                source ? { ...searchParams, source } : searchParams,
                router.values.hashParams
            )
        }
        return {
            forwardToRepo: () => {
                if (values.githubSources) {
                    forward()
                } else if (!values.githubSourcesLoading) {
                    actions.loadGithubSources()
                }
            },
            loadGithubSourcesSuccess: () => {
                if (values.pendingForward) {
                    forward()
                }
            },
            loadGithubSourcesFailure: () => {
                actions.clearPendingForward()
                actions.noRepoToForward()
            },
        }
    }),

    urlToAction(({ actions, values }) => ({
        ...Object.fromEntries(LEGACY_PATHS.map((pattern) => [pattern, () => actions.forwardToRepo()])),
        ...Object.fromEntries(
            REPO_PATHS.map((pattern) => [
                pattern,
                ({ repoOwner, repoName }: Record<string, string | undefined>) => {
                    const repo = `${repoOwner}/${repoName}`
                    if (values.currentTeamId && values.lastRepo !== repo) {
                        actions.rememberRepo(values.currentTeamId, repo)
                    }
                },
            ])
        ),
    })),
])
