export const ciExplorerLogic = kea<ciExplorerLogicType>([
    path(['products', 'engineering_analytics', 'frontend', 'scenes', 'ciExplorerLogic']),
    props({} as CIExplorerLogicProps),
    key((props) => `${props.repoOwner}/${props.repoName}#${props.number}@${props.sourceId ?? ''}`),

    actions({
        selectPush: (headSha: string) => ({ headSha }),
        setFocus: (nodeId: string | null) => ({ nodeId }),
    }),

    loaders(({ props, values }) => ({
        lifecycle: [
            null as PRLifecycleApi | null,
            {
                loadLifecycle: async (): Promise<PRLifecycleApi | null> =>
                    await engineeringAnalyticsPrLifecycle(projectId(), {
                        pr_number: props.number,
                        repo: `${props.repoOwner}/${props.repoName}`,
                        source_id: props.sourceId ?? undefined,
                    }),
            },
        ],
        prRuns: [
            null as WorkflowRunDetailApi[] | null,
            {
                loadPrRuns: async (): Promise<WorkflowRunDetailApi[]> =>
                    await engineeringAnalyticsPrRuns(projectId(), {
                        pr_number: props.number,
                        repo: `${props.repoOwner}/${props.repoName}`,
                        source_id: props.sourceId ?? undefined,
                    }),
            },
        ],
        jobsByRun: [
            {} as Record<string, WorkflowJobApi[]>,
            {
                loadJobs: async (runs: WorkflowRun[]): Promise<Record<string, WorkflowJobApi[]>> => {
                    const loaded = await Promise.all(
                        runs.map(async (run): Promise<[string, WorkflowJobApi[]] | null> => {
                            const cacheKey = runJobsKey(run)
                            if (cacheKey === null || run.runId === null) {
                                return null
                            }
                            const jobs = await engineeringAnalyticsWorkflowJobs(projectId(), {
                                run_id: run.runId,
                                ci_engine: run.ciEngine ?? undefined,
                                run_attempt: run.runAttempt ?? undefined,
                                source_id: props.sourceId ?? undefined,
                                repo: `${props.repoOwner}/${props.repoName}`,
                            })
                            return [cacheKey, jobs]
                        })
                    )
                    // Read after the await, so two pushes loading at once do not overwrite each other.
                    return { ...values.jobsByRun, ...Object.fromEntries(loaded.filter((entry) => entry !== null)) }
                },
            },
        ],
        // Keyed by workflow id. A workflow has no entry until its graph is placed.
        layouts: [
            {} as Record<string, CIExplorerLayout>,
            {
                loadLayouts: async (workflows: CIExplorerWorkflow[]): Promise<Record<string, CIExplorerLayout>> => {
                    const elk = await getElk()
                    const placed = await Promise.all(
                        workflows.map(
                            async (workflow): Promise<[string, CIExplorerLayout]> => [
                                workflow.id,
                                await layoutWorkflow(elk, workflow),
                            ]
                        )
                    )
                    return { ...values.layouts, ...Object.fromEntries(placed) }
                },
            },
        ],
    })),

    reducers({
        // Null follows the newest push.
        selectedHeadSha: [null as string | null, { selectPush: (_, { headSha }) => headSha }],
        focusedNodeId: [
            null as string | null,
            {
                setFocus: (_, { nodeId }) => nodeId,
                selectPush: () => null,
            },
        ],
        loadFailed: [
            false,
            {
                loadPrRuns: () => false,
                loadPrRunsFailure: () => true,
            },
        ],
    }),

    selectors({
        repoOwner: [() => [(_, p: CIExplorerLogicProps) => p.repoOwner], (repoOwner: string): string => repoOwner],
        repoName: [() => [(_, p: CIExplorerLogicProps) => p.repoName], (repoName: string): string => repoName],
        sourceId: [
            () => [(_, p: CIExplorerLogicProps) => p.sourceId],
            (sourceId: string | null): string | null => sourceId,
        ],
        // Newest push first.
        pushes: [
            (s) => [s.prRuns],
            (prRuns: WorkflowRunDetailApi[] | null): PrCommitRuns[] => groupRunsByCommit(prRuns ?? []),
        ],
        activePush: [
            (s) => [s.pushes, s.selectedHeadSha],
            (pushes: PrCommitRuns[], selectedHeadSha: string | null): PrCommitRuns | null =>
                pushes.find((push) => push.headSha === selectedHeadSha) ?? pushes[0] ?? null,
        ],
        // A re-run replaces the earlier attempt, as it does on GitHub's checks list.
        workflowRuns: [
            (s) => [s.activePush],
            (activePush: PrCommitRuns | null): WorkflowRun[] => {
                const latest = new Map<string, WorkflowRun>()
                for (const run of activePush?.runs ?? []) {
                    const seen = latest.get(run.workflow)
                    if (!seen || (run.startedAt ?? '') > (seen.startedAt ?? '')) {
                        latest.set(run.workflow, run)
                    }
                }
                return [...latest.values()]
            },
        ],
        workflows: [
            (s) => [s.workflowRuns, s.jobsByRun],
            (workflowRuns: WorkflowRun[], jobsByRun: Record<string, WorkflowJobApi[]>): CIExplorerWorkflow[] =>
                buildWorkflows(workflowRuns, jobsByRun),
        ],
        focusLevels: [
            (s) => [s.workflows, s.focusedNodeId],
            (workflows: CIExplorerWorkflow[], focusedNodeId: string | null): CIExplorerFocusLevel[] =>
                focusPath(workflows, focusedNodeId),
        ],
        focusedJob: [
            (s) => [s.workflows, s.focusedNodeId],
            (
                workflows: CIExplorerWorkflow[],
                focusedNodeId: string | null
            ): { job: WorkflowJobApi; run: WorkflowRun } | null => focusedJob(workflows, focusedNodeId),
        ],
        pushDurationSeconds: [
            (s) => [s.activePush],
            (activePush: PrCommitRuns | null): number | null =>
                activePush ? pushRoundOf(activePush.headSha, activePush.runs).wallSeconds : null,
        ],
        breadcrumbs: [
            (s, p) => [p.repoOwner, p.repoName, p.number, s.sourceId, router.selectors.searchParams],
            (
                repoOwner: string,
                repoName: string,
                number: number,
                sourceId: string | null,
                searchParams: Record<string, string | undefined>
            ): Breadcrumb[] => [
                {
                    key: 'EngineeringAnalytics',
                    name: 'Engineering analytics',
                    path: withScope(urls.engineeringAnalytics(), searchParams, sourceId),
                    iconType: 'health',
                },
                {
                    key: ['EngineeringAnalyticsPullRequest', `${repoOwner}/${repoName}#${number}`],
                    name: `${repoOwner}/${repoName} #${number}`,
                    path: withScope(
                        urls.engineeringAnalyticsPullRequest(repoOwner, repoName, number),
                        searchParams,
                        sourceId
                    ),
                    iconType: 'health',
                },
                {
                    key: ['EngineeringAnalyticsCIExplorer', `${repoOwner}/${repoName}#${number}`],
                    name: 'CI explorer',
                    iconType: 'health',
                },
            ],
        ],
    }),

    listeners(({ actions, values }) => {
        const loadMissingJobs = (): void => {
            const missing = values.workflowRuns.filter((run) => {
                const cacheKey = runJobsKey(run)
                return cacheKey !== null && !(cacheKey in values.jobsByRun)
            })
            if (missing.length) {
                actions.loadJobs(missing)
            }
        }
        const loadMissingLayouts = (): void => {
            const missing = values.workflows.filter(
                (workflow) => workflow.items !== null && !(workflow.id in values.layouts)
            )
            if (missing.length) {
                actions.loadLayouts(missing)
            }
        }
        return {
            loadPrRunsSuccess: loadMissingJobs,
            selectPush: () => {
                loadMissingJobs()
                loadMissingLayouts()
            },
            loadJobsSuccess: loadMissingLayouts,
        }
    }),

    afterMount(({ actions }) => {
        actions.loadLifecycle()
        actions.loadPrRuns()
    }),
])
