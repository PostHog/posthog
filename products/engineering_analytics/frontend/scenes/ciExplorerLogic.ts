// pinned: URL search params. Renaming one breaks shared links.
const VIEW_PARAM = 'view'
const SHA_PARAM = 'sha'
const NODE_PARAM = 'node'
// pinned: analytics event names. Renaming one breaks the insights built on it.
const EVENT_VIEWED = 'ci explorer viewed'
const EVENT_DRAWER_OPENED = 'ci explorer drawer opened'
const EVENT_REFRESHED = 'ci explorer refreshed'
const CI_EXPLORER_PATH_END = '/ci-explorer'
const CI_EXPLORER_ROUTE = `/engineering-analytics/repos/:repoOwner/:repoName/pull-requests/:number${CI_EXPLORER_PATH_END}`

/** The search params that put the explorer at `location`, keeping every param that is not the explorer's own. */
function locationSearchParams(current: Record<string, any>, location: CIExplorerLocation): Record<string, any> {
    const searchParams = { ...current }
    const own: [string, string | null][] = [
        [VIEW_PARAM, location.view === 'activity' ? 'activity' : null],
        [SHA_PARAM, location.headSha],
        [NODE_PARAM, location.nodeId],
    ]
    for (const [param, value] of own) {
        if (value === null) {
            delete searchParams[param]
        } else {
            searchParams[param] = value
        }
    }
    return searchParams
}

function jobInsightsKey(job: WorkflowJobApi): string {
    return `${job.ci_engine ?? ''}:${job.run_id}:${job.id}`
}

function runJobsKey(run: WorkflowRun): string | null {
    return run.runId === null ? null : jobCacheKey(run.runId, run.runAttempt, run.ciEngine)
}

function workflowsOfNodes(workflows: CIExplorerWorkflow[], nodeIds: (string | null)[]): CIExplorerWorkflow[] {
    return workflows.filter(
        (workflow) =>
            workflow.items !== null && nodeIds.some((id) => id !== null && `${id}/`.startsWith(`${workflow.id}/`))
    )
}

