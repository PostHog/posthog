export type doraLogicType = MakeLogicType<doraLogicValues, doraLogicActions, Record<string, any>, doraLogicMeta>

export const doraLogic = kea<doraLogicType>([
    path(['products', 'engineering_analytics', 'frontend', 'scenes', 'doraLogic']),

    connect(() => ({
        values: [
            engineeringAnalyticsFiltersLogic,
            ['dateFrom', 'dateTo'],
            engineeringAnalyticsLogic,
            ['sourceId', 'scopeRepo', 'notConnected'],
        ],
    })),

    actions({
        setEnvironments: (environments: string[]) => ({ environments }),
        setExcludeOutliers: (excludeOutliers: boolean) => ({ excludeOutliers }),
        setGithubTeam: (githubTeam: string | null) => ({ githubTeam }),
        setGranularity: (granularity: DoraGranularity | null) => ({ granularity }),
        resetGranularity: true,
        toggleLeadTimeStages: true,
    }),

    loaders(({ values }) => ({
        dora: [
            null as DoraOverviewApi | null,
            {
                loadDora: async (_: void, breakpoint): Promise<DoraOverviewApi> => {
                    const response = await engineeringAnalyticsDora(projectId(), {
                        date_from: values.dateFrom ?? undefined,
                        date_to: values.dateTo ?? undefined,
                        environment: values.environments.length ? values.environments : undefined,
                        github_team: values.githubTeam ?? undefined,
                        granularity: values.granularity ?? undefined,
                        source_id: values.sourceId ?? undefined,
                        repo: values.scopeRepo ?? undefined,
                    })
                    // breakpoint() throws if a newer loadDora call has started, discarding this stale response.
                    breakpoint()
                    return response
                },
            },
        ],
    })),

    reducers(() => ({
        // Non-400 failure only; the shared 400 "not connected" state comes from engineeringAnalyticsLogic.
        doraFailed: [
            false,
            {
                loadDora: () => false,
                loadDoraSuccess: () => false,
                loadDoraFailure: () => true,
            },
        ],
        // Empty means the backend's default scope: every production environment, falling back
        // to the busiest persistent one. Reset on a source/repo scope change: an
        // environment or team from the old repo may not exist on the new one, and would
        // otherwise be sent as a silently-empty exact filter.
        environments: [
            [] as string[],
            {
                setEnvironments: (_, { environments }) => environments,
                [engineeringAnalyticsLogic.actionTypes.setSourceId]: () => [],
                [engineeringAnalyticsLogic.actionTypes.setScope]: () => [],
            },
        ],
        granularity: [
            null as DoraGranularity | null,
            {
                setGranularity: (_, { granularity }) => granularity,
                resetGranularity: () => null,
            },
        ],
        showAllLeadTimeStages: [
            false,
            {
                toggleLeadTimeStages: (state: boolean) => !state,
            },
        ],
        excludeOutliers: [
            false,
            {
                setExcludeOutliers: (_: boolean, { excludeOutliers }: { excludeOutliers: boolean }) => excludeOutliers,
            },
        ],
        githubTeam: [
            null as string | null,
            {
                setGithubTeam: (_, { githubTeam }) => githubTeam,
                [engineeringAnalyticsLogic.actionTypes.setSourceId]: () => null,
                [engineeringAnalyticsLogic.actionTypes.setScope]: () => null,
            },
        ],
    })),

    selectors({
        boxPlotBuckets: [
            (s) => [s.dora],
            (dora: DoraOverviewApi | null): BoxPlotBucket[] =>
                toBoxPlotBuckets(dora?.merge_to_deploy_series, dora?.series_granularity ?? 'day'),
        ],
        openToMergeBuckets: [
            (s) => [s.dora],
            (dora: DoraOverviewApi | null): BoxPlotBucket[] =>
                toBoxPlotBuckets(dora?.open_to_merge_series, dora?.series_granularity ?? 'day'),
        ],
        openToDeployBuckets: [
            (s) => [s.dora],
            (dora: DoraOverviewApi | null): BoxPlotBucket[] =>
                toBoxPlotBuckets(dora?.open_to_deploy_series, dora?.series_granularity ?? 'day'),
        ],
        frequencyCounts: [
            (s) => [s.dora],
            (dora: DoraOverviewApi | null): number[] =>
                (dora?.deployment_frequency_series ?? []).map((bucket) => bucket.deployment_count),
        ],
        // ISO bucket starts for the time-series frequency chart — it formats its own axis and
        // tooltip labels from the granularity, so it needs the raw timestamps, not display strings.
        frequencyIsoLabels: [
            (s) => [s.dora],
            (dora: DoraOverviewApi | null): string[] =>
                (dora?.deployment_frequency_series ?? []).map((bucket) => bucket.bucket_start),
        ],
        environmentScopeLabel: [
            (s) => [s.dora, s.environments],
            (dora: DoraOverviewApi | null, environments: string[]): string =>
                environments.length
                    ? environments.join(', ')
                    : !dora
                      ? 'production'
                      : dora.environment_scope === 'persistent'
                        ? 'all persistent environments'
                        : dora.environment_scope,
        ],
        // With environments selected, environment_scope echoes the picks, so the resolved default
        // can only be offered while the selection is empty; picked names stay selectable options.
        environmentOptions: [
            (s) => [s.dora, s.environments],
            (dora: DoraOverviewApi | null, environments: string[]): { key: string; label: string }[] => {
                const names = new Set([...(dora?.environments ?? []), ...environments])
                return [...names].map((name) => ({ key: name, label: name }))
            },
        ],
        githubTeamOptions: [
            (s) => [s.dora],
            (dora: DoraOverviewApi | null): DoraScopeOption[] => [
                { value: null, label: 'All teams' },
                ...(dora?.github_teams ?? []).map((slug) => ({ value: slug as string | null, label: slug })),
            ],
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        setEnvironments: () => actions.loadDora(),
        setGithubTeam: () => actions.loadDora(),
        // Grouping and the date range co-adjust, sharing insights' interval mechanism: picking a
        // grouping snaps the range to one that fits it (the shared intervals map, e.g. hour ->
        // today), and a range change hands grouping back to the backend's automatic fit — so an
        // hour grouping can never span a year's worth of buckets.
        setGranularity: ({ granularity }) => {
            const newDateFrom = granularity ? intervals[granularity].newDateFrom : undefined
            if (newDateFrom) {
                cache.snappingRangeToGranularity = true
                engineeringAnalyticsFiltersLogic.actions.setDateRange(newDateFrom, null)
                return // the setDateRange listener below reloads
            }
            actions.loadDora()
        },
        [engineeringAnalyticsFiltersLogic.actionTypes.setDateRange]: () => {
            if (cache.snappingRangeToGranularity) {
                cache.snappingRangeToGranularity = false
            } else if (values.granularity !== null) {
                actions.resetGranularity()
            }
            actions.loadDora()
        },
        [engineeringAnalyticsLogic.actionTypes.setSourceId]: () => actions.loadDora(),
        [engineeringAnalyticsLogic.actionTypes.refresh]: () => actions.loadDora(),
    })),

    afterMount(({ actions }) => {
        actions.loadDora()
    }),
])
