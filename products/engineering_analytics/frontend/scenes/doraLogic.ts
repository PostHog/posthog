import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiConfig } from 'lib/api'

import type { BoxPlotBucket } from '../components/MergeToDeployBoxPlot'
import { engineeringAnalyticsDora } from '../generated/api'
import type { DoraOverviewApi } from '../generated/api.schemas'
import { engineeringAnalyticsFiltersLogic } from './engineeringAnalyticsFiltersLogic'
import { engineeringAnalyticsLogic, formatBucket, type WorkflowGranularity } from './engineeringAnalyticsLogic'

const projectId = (): string => String(ApiConfig.getCurrentProjectId())

const bucketLabel = (bucketStart: string, granularity: string): string =>
    formatBucket(bucketStart, granularity as WorkflowGranularity)

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface doraLogicValues {
    dateFrom: string | null // engineeringAnalyticsFiltersLogic
    dateTo: string | null // engineeringAnalyticsFiltersLogic
    notConnected: boolean // engineeringAnalyticsLogic
    scopeRepo: string | null // engineeringAnalyticsLogic
    sourceId: string | null // engineeringAnalyticsLogic
    boxPlotBuckets: BoxPlotBucket[]
    dora: DoraOverviewApi | null
    doraFailed: boolean
    doraLoading: boolean
    environment: string | null
    frequencyCounts: number[]
    frequencyLabels: string[]
    githubTeam: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface doraLogicActions {
    loadDora: () => any
    loadDoraFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadDoraSuccess: (
        dora: DoraOverviewApi,
        payload?: any
    ) => {
        dora: DoraOverviewApi
        payload?: any
    }
    setEnvironment: (environment: string | null) => {
        environment: string | null
    }
    setGithubTeam: (githubTeam: string | null) => {
        githubTeam: string | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface doraLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        boxPlotBuckets: (dora: DoraOverviewApi | null) => BoxPlotBucket[]
        frequencyCounts: (dora: DoraOverviewApi | null) => number[]
        frequencyLabels: (dora: DoraOverviewApi | null) => string[]
    }
}

export type doraLogicType = MakeLogicType<doraLogicValues, doraLogicActions, Record<string, any>, doraLogicMeta>

export const doraLogic = kea<doraLogicType>([
    path(['products', 'engineering_analytics', 'frontend', 'scenes', 'doraLogic']),

    connect(() => ({
        values: [
            engineeringAnalyticsFiltersLogic,
            ['dateFrom', 'dateTo'],
            engineeringAnalyticsLogic,
            ['sourceId', 'scopeRepo', 'notConnected'],
        ],
    })),

    actions({
        setEnvironment: (environment: string | null) => ({ environment }),
        setGithubTeam: (githubTeam: string | null) => ({ githubTeam }),
    }),

    loaders(({ values }) => ({
        dora: [
            null as DoraOverviewApi | null,
            {
                loadDora: async (): Promise<DoraOverviewApi> =>
                    await engineeringAnalyticsDora(projectId(), {
                        date_from: values.dateFrom ?? undefined,
                        date_to: values.dateTo ?? undefined,
                        environment: values.environment ?? undefined,
                        github_team: values.githubTeam ?? undefined,
                        source_id: values.sourceId ?? undefined,
                        repo: values.scopeRepo ?? undefined,
                    }),
            },
        ],
    })),

    reducers({
        // Non-400 failure only; the shared 400 "not connected" state comes from engineeringAnalyticsLogic.
        doraFailed: [
            false,
            {
                loadDora: () => false,
                loadDoraSuccess: () => false,
                loadDoraFailure: () => true,
            },
        ],
        // null means the backend's default scope: production-marked deploys, falling back to all.
        environment: [
            null as string | null,
            {
                setEnvironment: (_, { environment }) => environment,
            },
        ],
        githubTeam: [
            null as string | null,
            {
                setGithubTeam: (_, { githubTeam }) => githubTeam,
            },
        ],
    }),

    selectors({
        boxPlotBuckets: [
            (s) => [s.dora],
            (dora: DoraOverviewApi | null): BoxPlotBucket[] =>
                (dora?.merge_to_deploy_series ?? []).map((bucket) => ({
                    label: bucketLabel(bucket.bucket_start, dora?.series_granularity ?? 'day'),
                    count: bucket.deployed_pr_count,
                    minSeconds: bucket.min_seconds,
                    p25Seconds: bucket.p25_seconds,
                    p50Seconds: bucket.p50_seconds,
                    meanSeconds: bucket.mean_seconds,
                    p75Seconds: bucket.p75_seconds,
                    maxSeconds: bucket.max_seconds,
                })),
        ],
        frequencyCounts: [
            (s) => [s.dora],
            (dora: DoraOverviewApi | null): number[] =>
                (dora?.deployment_frequency_series ?? []).map((bucket) => bucket.deployment_count),
        ],
        frequencyLabels: [
            (s) => [s.dora],
            (dora: DoraOverviewApi | null): string[] =>
                (dora?.deployment_frequency_series ?? []).map(
                    (bucket) =>
                        `${bucketLabel(bucket.bucket_start, dora?.series_granularity ?? 'day')}: ${bucket.deployment_count} deploy${bucket.deployment_count === 1 ? '' : 's'}`
                ),
        ],
    }),

    listeners(({ actions }) => ({
        setEnvironment: () => actions.loadDora(),
        setGithubTeam: () => actions.loadDora(),
        [engineeringAnalyticsFiltersLogic.actionTypes.setDateRange]: () => actions.loadDora(),
        [engineeringAnalyticsLogic.actionTypes.setSourceId]: () => actions.loadDora(),
        [engineeringAnalyticsLogic.actionTypes.refresh]: () => actions.loadDora(),
    })),

    afterMount(({ actions }) => {
        actions.loadDora()
    }),
])
