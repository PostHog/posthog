export const teamDetailLogic = kea<teamDetailLogicType>([
    path(['products', 'engineering_analytics', 'frontend', 'scenes', 'teamDetailLogic']),
    props({} as TeamDetailLogicProps),
    key((props) => `${props.ownerTeam}@${props.sourceId ?? ''}`),

    connect(() => ({
        values: [
            engineeringAnalyticsFiltersLogic,
            ['dateFrom', 'dateTo'],
            engineeringAnalyticsLogic,
            ['trunkQuarantineTestsByTeam'],
        ],
        actions: [engineeringAnalyticsFiltersLogic, ['setDateRange']],
    })),
    actions({
        loadWindowedSections: true,
    }),

    loaders(({ props, values }) => ({
        activity: [
            null as TeamActivityData | null,
            {
                loadActivity: async (): Promise<TeamActivityData> => {
                    // Current-state list on the fixed default window, deliberately outside the
                    // window picker's scope (the panel rule in ../AGENTS.md).
                    const data = await engineeringAnalyticsTeamCiActivity(projectId(), {
                        owner_team: props.ownerTeam,
                        date_from: DEFAULT_TEAMS_WINDOW,
                        source_id: props.sourceId ?? undefined,
                    })
                    return {
                        tests: data.tests.map((t) => ({
                            runner: t.runner,
                            nodeid: t.nodeid,
                            selector: t.selector,
                            signalCount: t.signal_count,
                            lastSeenAt: t.last_seen_at,
                        })),
                        truncatedTests: data.truncated_tests,
                    }
                },
            },
        ],
        healthRow: [
            null as TeamCIHealthRow | null,
            {
                loadHealthRow: async (): Promise<TeamCIHealthRow | null> => {
                    const data = await engineeringAnalyticsTeamCiHealth(projectId(), {
                        date_from: values.dateFrom ?? DEFAULT_TEAMS_WINDOW,
                        date_to: values.dateTo ?? undefined,
                        owner_team: props.ownerTeam,
                        limit: 1,
                        source_id: props.sourceId ?? undefined,
                    })
                    const item = data.items[0]
                    return item ? toTeamCIHealthRow(item) : null
                },
            },
        ],
        mergeTrend: [
            null as TeamMergeTrendData | null,
            {
                loadMergeTrend: async (): Promise<TeamMergeTrendData | null> => {
                    // 'unowned' is an ownership gap, not an org team; a membership join has no meaning there.
                    if (props.ownerTeam === UNOWNED_TEAM) {
                        return null
                    }
                    const data = await engineeringAnalyticsTeamMergeTrend(projectId(), {
                        owner_team: props.ownerTeam,
                        date_from: values.dateFrom ?? DEFAULT_TEAMS_WINDOW,
                        date_to: values.dateTo ?? undefined,
                        source_id: props.sourceId ?? undefined,
                    })
                    return {
                        hasMembershipData: data.has_membership_data,
                        points: data.points.map((p) => ({
                            day: p.day,
                            medianSeconds: p.median_seconds ?? null,
                            averageSeconds: p.average_seconds ?? null,
                        })),
                    }
                },
            },
        ],
    })),
    reducers({
        activityStatus: [
            'ok' as LoaderStatus,
            {
                loadActivity: () => 'ok',
                loadActivitySuccess: () => 'ok',
                loadActivityFailure: (_, { errorObject }) => loaderStatusFromError(errorObject),
            },
        ],
        healthRowStatus: [
            'ok' as LoaderStatus,
            {
                loadHealthRow: () => 'ok',
                loadHealthRowSuccess: () => 'ok',
                loadHealthRowFailure: (_, { errorObject }) => loaderStatusFromError(errorObject),
            },
        ],
        mergeTrendStatus: [
            'ok' as LoaderStatus,
            {
                loadMergeTrend: () => 'ok',
                loadMergeTrendSuccess: () => 'ok',
                loadMergeTrendFailure: (_, { errorObject }) => loaderStatusFromError(errorObject),
            },
        ],
    }),
    selectors({
        ownerTeam: [(_, p) => [p.ownerTeam], (ownerTeam: string) => ownerTeam],
        sourceId: [(_, p) => [p.sourceId], (sourceId: string | null) => sourceId],
        /** owners.yaml team names are GitHub team slugs (checked by `hogli owners:lint --live`). Null for
         *  unowned surfaces, which have no GitHub team. */
        deliveryScope: [
            (s) => [s.ownerTeam],
            (ownerTeam: string): DeliveryScope | null =>
                ownerTeam === UNOWNED_TEAM ? null : { kind: 'github_team', githubTeam: ownerTeam },
        ],
        quarantinedTests: [
            (s) => [s.trunkQuarantineTestsByTeam, s.ownerTeam],
            (
                trunkQuarantineTestsByTeam: Record<string, TrunkQuarantinedTestRow[]>,
                ownerTeam: string
            ): TrunkQuarantinedTestRow[] => trunkQuarantineTestsByTeam[ownerTeam] ?? [],
        ],
        breadcrumbs: [
            (s) => [s.ownerTeam, s.sourceId, router.selectors.searchParams],
            (
                ownerTeam: string,
                sourceId: string | null,
                searchParams: Record<string, string | undefined>
            ): Breadcrumb[] => [
                {
                    key: 'EngineeringAnalytics',
                    name: 'Engineering analytics',
                    path: withScope(urls.engineeringAnalytics(), searchParams, sourceId),
                    iconType: 'health',
                },
                {
                    key: 'EngineeringAnalyticsTeams',
                    name: 'Teams',
                    path: withScope(urls.engineeringAnalyticsTeams(), searchParams, sourceId),
                    iconType: 'health',
                },
                {
                    key: ['EngineeringAnalyticsTeam', ownerTeam],
                    name: teamLabel(ownerTeam),
                    iconType: 'health',
                },
            ],
        ],
        /** Quill-ready daily series on the backend's own day buckets. Gaps carry the last values
         *  forward: a day without merges means "nothing merged", not instant merges, so
         *  zero-filling would draw a false dip. Null when nothing merged in the window. */
        mergeTrendSeries: [
            (s) => [s.mergeTrend],
            (
                mergeTrend: TeamMergeTrendData | null
            ): { labels: string[]; median: number[]; average: number[] } | null => {
                if (!mergeTrend?.hasMembershipData) {
                    return null
                }
                const labels: string[] = []
                const median: number[] = []
                const average: number[] = []
                let lastDay: Dayjs | null = null
                let lastMedian = 0
                let lastAverage = 0
                for (const point of mergeTrend.points) {
                    const day = dayjs(point.day)
                    if (lastDay) {
                        for (let gap: Dayjs = lastDay.add(1, 'day'); gap.isBefore(day); gap = gap.add(1, 'day')) {
                            labels.push(gap.toISOString())
                            median.push(lastMedian)
                            average.push(lastAverage)
                        }
                    }
                    const medianValue: number | null = point.medianSeconds ?? (lastDay ? lastMedian : null)
                    const averageValue: number | null = point.averageSeconds ?? (lastDay ? lastAverage : null)
                    if (medianValue === null || averageValue === null) {
                        continue // Leading trim: no data yet to carry forward.
                    }
                    labels.push(day.toISOString())
                    median.push(medianValue)
                    average.push(averageValue)
                    lastDay = day
                    lastMedian = medianValue
                    lastAverage = averageValue
                }
                return labels.length ? { labels, median, average } : null
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        loadWindowedSections: () => {
            // The team endpoints reject windows over 30 days, so reset the shared picker rather than
            // show a window the sections cannot load.
            if (!isTeamsDateRange(values.dateFrom, values.dateTo)) {
                actions.setDateRange(DEFAULT_TEAMS_WINDOW, null)
                return
            }
            actions.loadMergeTrend()
            actions.loadHealthRow()
        },
        setDateRange: () => {
            actions.loadWindowedSections()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadActivity()
        actions.loadWindowedSections()
    }),
])
