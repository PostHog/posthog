import { MakeLogicType, afterMount, kea, key, listeners, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'

import { betsEventsList, betsFundCreate, betsNodesList, betsRetrieve, betsVerdictCreate } from './generated/api'
import type { BetDTOApi, BetEventDTOApi, BetNodeDTOApi, RecordVerdictApi } from './generated/api.schemas'

export type BetEventRecord = BetEventDTOApi
export type BetNodeRecord = BetNodeDTOApi
export type Verdict = RecordVerdictApi['verdict']

// A managed run keeps producing events/nodes after the initial load — poll while it's live.
const LIVE_RUN_POLL_INTERVAL_MS = 2500

export interface FoundryBetLogicProps {
    id: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface foundryBetLogicValues {
    bet: BetDTOApi | null
    betLoading: boolean
    events: BetEventRecord[]
    eventsLoading: boolean
    nodes: BetNodeRecord[]
    nodesLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface foundryBetLogicActions {
    loadBet: () => any
    loadBetFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadBetSuccess: (bet: BetDTOApi | null, payload?: any) => any
    fund: () => any
    fundFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    fundSuccess: (bet: BetDTOApi | null, payload?: any) => any
    recordVerdict: (verdict: Verdict) => any
    recordVerdictFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    recordVerdictSuccess: (bet: BetDTOApi | null, payload?: any) => any
    loadEvents: () => any
    loadEventsFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadEventsSuccess: (events: BetEventRecord[], payload?: any) => any
    loadNodes: () => any
    loadNodesFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadNodesSuccess: (nodes: BetNodeRecord[], payload?: any) => any
}

export type foundryBetLogicType = MakeLogicType<foundryBetLogicValues, foundryBetLogicActions, FoundryBetLogicProps>

const projectId = (): string => String(teamLogic.values.currentTeamId)

// A managed run keeps producing events/nodes on its own; these are the non-terminal states where
// something might still be happening unattended — including 'funded', since a managed bet's
// funded -> building transition itself happens inside the workflow, not from a user action here.
const LIVE_STATES = new Set(['funded', 'building', 'gated'])

export const foundryBetLogic = kea<foundryBetLogicType>([
    path(['products', 'foundry', 'frontend', 'foundryBetLogic']),
    props({} as FoundryBetLogicProps),
    key((props) => props.id),
    loaders(({ props }) => ({
        bet: [
            null as BetDTOApi | null,
            {
                loadBet: async (): Promise<BetDTOApi> => await betsRetrieve(projectId(), props.id),
                fund: async (): Promise<BetDTOApi> => await betsFundCreate(projectId(), props.id),
                recordVerdict: async (verdict: Verdict): Promise<BetDTOApi> =>
                    await betsVerdictCreate(projectId(), props.id, { verdict }),
            },
        ],
        events: [
            [] as BetEventRecord[],
            {
                loadEvents: async (): Promise<BetEventRecord[]> => await betsEventsList(projectId(), props.id),
            },
        ],
        nodes: [
            [] as BetNodeRecord[],
            {
                loadNodes: async (): Promise<BetNodeRecord[]> => await betsNodesList(projectId(), props.id),
            },
        ],
    })),
    listeners(({ actions, cache }) => {
        // Re-poll while a run is still live (managed execution, or an in-flight gate check);
        // stops itself once the bet leaves a live state, and never runs more than one poller.
        const syncLiveRunPoll = (bet: BetDTOApi | null): void => {
            if (bet && LIVE_STATES.has(bet.state)) {
                cache.disposables.add(() => {
                    const id = window.setInterval(() => {
                        actions.loadBet()
                        actions.loadEvents()
                        actions.loadNodes()
                    }, LIVE_RUN_POLL_INTERVAL_MS)
                    return () => window.clearInterval(id)
                }, 'liveRunPoll')
            } else {
                cache.disposables.dispose('liveRunPoll')
            }
        }
        return {
            fundSuccess: ({ bet }) => {
                actions.loadEvents()
                actions.loadNodes()
                syncLiveRunPoll(bet)
                lemonToast.success('Bet funded: feature flag and draft experiment created')
            },
            recordVerdictSuccess: ({ bet }) => {
                actions.loadEvents()
                syncLiveRunPoll(bet)
            },
            fundFailure: ({ error }) => {
                lemonToast.error(error ?? 'Failed to fund bet')
            },
            recordVerdictFailure: ({ error }) => {
                lemonToast.error(error ?? 'Failed to record verdict')
            },
            loadBetSuccess: ({ bet }) => {
                syncLiveRunPoll(bet)
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadBet()
        actions.loadEvents()
        actions.loadNodes()
    }),
])
