import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { betsCreate, betsList } from './generated/api'
import type { BetDTOApi } from './generated/api.schemas'

export type BetRecord = BetDTOApi

export interface NewBetForm {
    slug: string
    hypothesis: string
    metric_name: string
    metric_target: string
    guardrail: string
    budget_usd: number | undefined
}

const NEW_BET_DEFAULTS: NewBetForm = {
    slug: '',
    hypothesis: '',
    metric_name: '',
    metric_target: '',
    guardrail: '',
    budget_usd: 50,
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface foundryLogicValues {
    bets: BetRecord[]
    betsLoading: boolean
    isNewBetModalOpen: boolean
    newBet: NewBetForm
    isNewBetSubmitting: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface foundryLogicActions {
    loadBets: () => any
    loadBetsFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadBetsSuccess: (bets: BetRecord[], payload?: any) => any
    showNewBetModal: () => any
    hideNewBetModal: () => any
    setNewBetField: (
        field: keyof NewBetForm,
        value: string | number | undefined
    ) => { field: keyof NewBetForm; value: string | number | undefined }
    submitNewBet: () => any
    setIsNewBetSubmitting: (isNewBetSubmitting: boolean) => { isNewBetSubmitting: boolean }
}

export type foundryLogicType = MakeLogicType<foundryLogicValues, foundryLogicActions>

export const foundryLogic = kea<foundryLogicType>([
    path(['products', 'foundry', 'frontend', 'foundryLogic']),
    actions({
        showNewBetModal: true,
        hideNewBetModal: true,
        setNewBetField: (field: keyof NewBetForm, value: string | number | undefined) => ({ field, value }),
        submitNewBet: true,
        setIsNewBetSubmitting: (isNewBetSubmitting: boolean) => ({ isNewBetSubmitting }),
    }),
    loaders(() => ({
        bets: [
            [] as BetRecord[],
            {
                loadBets: async (): Promise<BetRecord[]> => {
                    const projectId = String(teamLogic.values.currentTeamId)
                    return await betsList(projectId)
                },
            },
        ],
    })),
    reducers({
        isNewBetModalOpen: [
            false,
            {
                showNewBetModal: () => true,
                hideNewBetModal: () => false,
            },
        ],
        newBet: [
            NEW_BET_DEFAULTS,
            {
                setNewBetField: (state, { field, value }) => ({ ...state, [field]: value }),
                hideNewBetModal: () => NEW_BET_DEFAULTS,
            },
        ],
        isNewBetSubmitting: [
            false,
            {
                setIsNewBetSubmitting: (_, { isNewBetSubmitting }) => isNewBetSubmitting,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        submitNewBet: async () => {
            const form = values.newBet
            if (!form.slug || !form.hypothesis || !form.metric_name) {
                lemonToast.error('Slug, hypothesis and success metric are required')
                return
            }
            actions.setIsNewBetSubmitting(true)
            try {
                const projectId = String(teamLogic.values.currentTeamId)
                const bet = await betsCreate(projectId, {
                    slug: form.slug,
                    hypothesis: form.hypothesis,
                    success_metric: { name: form.metric_name, target: form.metric_target || undefined },
                    guardrails: form.guardrail ? [{ name: form.guardrail }] : [],
                    budget: form.budget_usd != null ? { usd: form.budget_usd } : {},
                })
                actions.hideNewBetModal()
                actions.loadBets()
                lemonToast.success(`Bet "${bet.slug}" drafted`)
                router.actions.push(urls.foundryBet(bet.id))
            } catch (error: any) {
                lemonToast.error(error?.detail ?? 'Failed to create bet')
            } finally {
                actions.setIsNewBetSubmitting(false)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadBets()
    }),
])
