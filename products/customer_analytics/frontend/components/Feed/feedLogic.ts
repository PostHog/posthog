import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api, { CountedPaginatedResponse } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'
import { userLogic } from 'scenes/userLogic'

import { signalsScoutConfigList } from 'products/signals/frontend/generated/api'
import type { SignalScoutConfigApi } from 'products/signals/frontend/generated/api.schemas'
import {
    buildSignalReportListOrdering,
    InboxSortDirection,
    InboxSortField,
} from 'products/signals/frontend/inbox/logics/inboxFiltersLogic'
import { SignalReport, SignalReportPriority, SignalReportStatus } from 'products/signals/frontend/inbox/types'
import { DismissalReasonValue } from 'products/signals/frontend/inbox/utils/dismissalReasons'

import type { UserType } from '../../../../../frontend/src/types'

// Matches every scout in the customer analytics family — new scouts only need a name
// starting with this prefix to show up in the feed.
export const CUSTOMER_ANALYTICS_SCOUT_PREFIX = 'signals-scout-customer-analytics'

const DEFAULT_SORT_FIELD: InboxSortField = 'priority'
const DEFAULT_SORT_DIRECTION: InboxSortDirection = 'asc'

// ponytail: single page of 100; add pagination when a team's scout reports outgrow it.
const REPORTS_LIMIT = 100

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface feedLogicValues {
    currentTeamId: number | null // teamLogic
    user: UserType | null // userLogic
    hasActiveFilters: boolean
    myReportsOnly: boolean
    priorityFilter: SignalReportPriority[]
    reports: SignalReport[]
    reportsResponse: CountedPaginatedResponse<SignalReport> | null
    reportsResponseLoading: boolean
    scoutConfigs: SignalScoutConfigApi[] | null
    scoutConfigsLoading: boolean
    scoutFilter: string[]
    scoutNames: string[]
    searchQuery: string
    sortDirection: InboxSortDirection
    sortField: InboxSortField
    statusFilter: SignalReportStatus | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
