const RESULTS_PER_PAGE = 50
const ACCOUNT_OPTIONS_LIMIT = 50

// Mirrors AccountNotesViewSet.ALLOWED_ORDERING. Kept here because the generated client types `ordering` as a plain string.
const ACCOUNT_NOTES_ORDERINGS = [
    '-account_name',
    '-created_at',
    '-created_by',
    '-last_modified_at',
    '-title',
    'account_name',
    'created_at',
    'created_by',
    'last_modified_at',
    'title',
] as const

export type AccountNotesListOrdering = (typeof ACCOUNT_NOTES_ORDERINGS)[number]

export const DEFAULT_NOTES_ORDERING: AccountNotesListOrdering = '-last_modified_at'

export type AccountFilterOption = { id: string; name: string }

// Type aliases rather than interfaces so the filters object stays assignable to the
// ColumnConfiguration `filters` index signature.
export type AccountNotesViewFilters = {
    search: string
    tags: string[]
    created_by: number[]
    assigned_to: number[]
    account_id: string | null
    account_name: string | null
}

export type AccountNotesViewState = {
    filters: AccountNotesViewFilters
    ordering: AccountNotesListOrdering
}

export const EMPTY_NOTES_VIEW_STATE: AccountNotesViewState = {
    filters: {
        search: '',
        tags: [],
        created_by: [],
        assigned_to: [],
        account_id: null,
        account_name: null,
    },
    ordering: DEFAULT_NOTES_ORDERING,
}

export function isAccountNotesListOrdering(value: unknown): value is AccountNotesListOrdering {
    return (ACCOUNT_NOTES_ORDERINGS as readonly unknown[]).includes(value)
}

// Maps the table's sorting state onto the backend's whitelisted `ordering` param.
export function sortingToOrdering(sorting: Sorting | null): AccountNotesListOrdering {
    if (!sorting) {
        return DEFAULT_NOTES_ORDERING
    }
    const ordering = sorting.order === -1 ? `-${sorting.columnKey}` : sorting.columnKey
    return isAccountNotesListOrdering(ordering) ? ordering : DEFAULT_NOTES_ORDERING
}

export function orderingToSorting(ordering: AccountNotesListOrdering): Sorting {
    return ordering.startsWith('-') ? { columnKey: ordering.slice(1), order: -1 } : { columnKey: ordering, order: 1 }
}

