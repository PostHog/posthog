import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { objectsEqual } from 'lib/utils/objects'
import { teamLogic } from 'scenes/teamLogic'

import {
    userCustomerAnalyticsConfigPartialUpdate,
    userCustomerAnalyticsConfigRetrieve,
} from 'products/customer_analytics/frontend/generated/api'
import type {
    TaskDigestCadenceEnumApi,
    TaskDigestPreferencesApi,
    UserCustomerAnalyticsConfigApi,
} from 'products/customer_analytics/frontend/generated/api.schemas'

import { AccountsEvents } from '../Accounts/constants'

const CURRENT_USER_CONFIG_ID = '@me'

interface TaskDigestSavePayload {
    source?: 'settings' | 'tasks'
}

/** Locally staged edits to the digest preferences, applied on Save. */
export interface TaskDigestDraft {
    enabled: boolean
    send_time: string
    cadence: TaskDigestCadenceEnumApi
}

function draftFromConfig(config: UserCustomerAnalyticsConfigApi | null): TaskDigestDraft {
    const digest: TaskDigestPreferencesApi | undefined = config?.task_digest
    return {
        enabled: digest?.enabled ?? false,
        send_time: digest?.send_time ?? '09:00',
        cadence: digest?.cadence ?? 'weekdays',
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface taskDigestLogicValues {
    currentTeamId: number | null // teamLogic
    timezone: string // teamLogic
    config: UserCustomerAnalyticsConfigApi | null
    configLoadFailed: boolean
    configLoading: boolean
    draft: TaskDigestDraft
    hasChanges: boolean
    isInitialLoading: boolean
    validSendTime: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface taskDigestLogicActions {
    loadConfig: () => any
    loadConfigFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadConfigSuccess: (
        config: UserCustomerAnalyticsConfigApi,
        payload?: any
    ) => {
        config: UserCustomerAnalyticsConfigApi
        payload?: any
    }
    resetDraft: () => {
        value: true
    }
    saveTaskDigest: (_payload?: TaskDigestSavePayload) => TaskDigestSavePayload
    saveTaskDigestFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    saveTaskDigestSuccess: (
        config: UserCustomerAnalyticsConfigApi,
        payload?: TaskDigestSavePayload
    ) => {
        config: UserCustomerAnalyticsConfigApi
        payload?: TaskDigestSavePayload
    }
    setDraft: (draft: Partial<TaskDigestDraft>) => {
        draft: Partial<TaskDigestDraft>
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface taskDigestLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        validSendTime: (draft: TaskDigestDraft) => boolean
        hasChanges: (draft: TaskDigestDraft, config: UserCustomerAnalyticsConfigApi | null) => boolean
        isInitialLoading: (configLoading: boolean, config: UserCustomerAnalyticsConfigApi | null) => boolean
    }
}

export type taskDigestLogicType = MakeLogicType<
    taskDigestLogicValues,
    taskDigestLogicActions,
    Record<string, any>,
    taskDigestLogicMeta
>

export const taskDigestLogic = kea<taskDigestLogicType>([
    path(['products', 'customerAnalytics', 'taskDigest', 'taskDigestLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId', 'timezone']],
    })),
    actions({
        setDraft: (draft: Partial<TaskDigestDraft>) => ({ draft }),
        resetDraft: true,
    }),
    loaders(({ values }) => ({
        config: [
            null as UserCustomerAnalyticsConfigApi | null,
            {
                loadConfig: async (): Promise<UserCustomerAnalyticsConfigApi> =>
                    await userCustomerAnalyticsConfigRetrieve(String(values.currentTeamId), CURRENT_USER_CONFIG_ID),
                // Sends only task_digest, so the user's pinned sidebar properties stay untouched.
                saveTaskDigest: async (_payload: TaskDigestSavePayload = {}): Promise<UserCustomerAnalyticsConfigApi> =>
                    await userCustomerAnalyticsConfigPartialUpdate(
                        String(values.currentTeamId),
                        CURRENT_USER_CONFIG_ID,
                        { task_digest: values.draft }
                    ),
            },
        ],
    })),
    reducers({
        configLoadFailed: [
            false,
            {
                loadConfig: () => false,
                loadConfigFailure: () => true,
                loadConfigSuccess: () => false,
            },
        ],
        draft: [
            draftFromConfig(null),
            {
                setDraft: (state, { draft }) => ({ ...state, ...draft }),
                loadConfigSuccess: (_, { config }) => draftFromConfig(config),
                saveTaskDigestSuccess: (_, { config }) => draftFromConfig(config),
            },
        ],
    }),
    selectors({
        validSendTime: [
            (s) => [s.draft],
            (draft: TaskDigestDraft): boolean => /^([01][0-9]|2[0-3]):[0-5][0-9]$/.test(draft.send_time),
        ],
        hasChanges: [
            (s) => [s.draft, s.config],
            (draft: TaskDigestDraft, config: UserCustomerAnalyticsConfigApi | null): boolean =>
                !objectsEqual(draft, draftFromConfig(config)),
        ],
        isInitialLoading: [
            (s) => [s.configLoading, s.config],
            (configLoading: boolean, config: UserCustomerAnalyticsConfigApi | null): boolean =>
                configLoading && config === null,
        ],
    }),
    // Failures get no listener: the global kea-loaders handler toasts and reports them, and the
    // load error banner runs off the configLoadFailed reducer.
    listeners(({ actions, values }) => ({
        resetDraft: () => {
            actions.setDraft(draftFromConfig(values.config))
        },
        saveTaskDigestSuccess: ({ config, payload }) => {
            lemonToast.success('Task digest preferences saved')
            posthog.capture(AccountsEvents.TaskDigestPreferencesSaved, {
                source: payload?.source ?? 'settings',
                enabled: config?.task_digest?.enabled ?? false,
                send_time: config?.task_digest?.send_time,
                cadence: config?.task_digest?.cadence,
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadConfig()
    }),
])
