export const PRODUCT_USAGE_OVERVIEW_KEY = 'customer-analytics-product-activity-overview'

export function buildProductUsageOverviewQuery(
    filters: ProductUsageFilters,
    tiles: AccountsOverviewTile[]
): AccountsTableQuery {
    return {
        ...buildProductUsageAccountsQuery(filters),
        useDefaultColumns: undefined,
        metrics: tiles.flatMap((tile) => {
            const metric = tileQueryMetric(tile)
            return metric ? [metric] : []
        }),
        tags: { product: 'customer_analytics', name: PRODUCT_USAGE_OVERVIEW_KEY },
    }
}

