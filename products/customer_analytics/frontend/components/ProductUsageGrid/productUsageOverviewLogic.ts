export const productUsageOverviewLogic = kea<productUsageOverviewLogicType>([
    path(['products', 'customerAnalytics', 'productUsageOverviewLogic']),
    connect(() => ({ values: [productUsageGridLogic, ['controls', 'currentTeamId', 'user']] })),
    loaders(({ values, cache }) => ({
        tiles: [
            null as AccountsOverviewTile[] | null,
            {
                loadTiles: async (_: unknown = undefined, breakpoint): Promise<AccountsOverviewTile[]> => {
                    const teamId = values.currentTeamId
                    const userId = values.user?.uuid
                    if (!teamId || !userId) {
                        return DEFAULT_TILES
                    }
                    const session = getAccountsViewSession(teamId, userId)
                    // Reuse unsaved Accounts configuration when navigating within this app session.
                    if (session.state) {
                        return session.state.tiles
                    }
                    const viewId = readAccountsViewId(teamId, userId) ?? readAccountsViewId(teamId)
                    if (!viewId) {
                        return DEFAULT_TILES
                    }
                    const controller = new AbortController()
                    cache.disposables.add(() => () => controller.abort(), 'overview-definition', {
                        pauseOnPageHidden: false,
                    })
                    const view = await columnConfigurationsRetrieve(String(teamId), viewId, {
                        signal: controller.signal,
                    })
                    breakpoint()
                    if (view.context_key !== ACCOUNTS_COLUMN_CONFIG_KEY) {
                        return DEFAULT_TILES
                    }
                    return deserializeAccountsView(view).tiles
                },
            },
        ],
    })),
    reducers({
        tilesError: [
            null as string | null,
            {
                loadTiles: () => null,
                loadTilesSuccess: () => null,
                loadTilesFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        reconciledTiles: [
            (s) => [s.tiles],
            (tiles: AccountsOverviewTile[] | null): AccountsOverviewTile[] =>
                (tiles ?? []).filter((tile) => tileQueryMetric(tile) !== null),
        ],
        query: [
            (s) => [s.controls, s.reconciledTiles],
            (controls: ProductUsageFilters, tiles: AccountsOverviewTile[]): AccountsTableQuery | null =>
                tiles.length ? buildProductUsageOverviewQuery(controls, tiles) : null,
        ],
    }),
    listeners(() => ({
        [productUsageGridLogic.actionTypes.refresh]: () =>
            dataNodeLogic.findMounted({ key: PRODUCT_USAGE_OVERVIEW_KEY })?.actions.loadData('force_async'),
    })),
    afterMount(({ actions }) => actions.loadTiles()),
])
