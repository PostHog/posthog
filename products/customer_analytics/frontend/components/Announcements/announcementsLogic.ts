export const announcementsLogic = kea<announcementsLogicType>([
    path(['products', 'customer_analytics', 'frontend', 'components', 'Announcements', 'announcementsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam'], userLogic, ['user']],
        actions: [teamLogic, ['loadCurrentTeamSuccess']],
    })),
    actions({
        setMessage: (message: string) => ({ message }),
        setSelectedChannelIds: (channelIds: string[]) => ({ channelIds }),
        submitAnnouncement: true,
        setSubmitting: (submitting: boolean) => ({ submitting }),
        setAccountSearch: (search: string) => ({ search }),
        setAccountTags: (tags: string[]) => ({ tags }),
        setAssignedTo: (userIds: number[]) => ({ userIds }),
        setAllUnassigned: (value: boolean) => ({ value }),
        setMyAccounts: (value: boolean) => ({ value }),
        clearAccountFilters: true,
        selectAllFilteredChannels: true,
        toggleChannel: (channelId: string) => ({ channelId }),
    }),
    loaders(({ values }) => ({
        announcements: [
            [] as AnnouncementApi[],
            {
                loadAnnouncements: async () => {
                    const response = await announcementsList(String(values.currentTeam?.id), { limit: 100 })
                    return response.results ?? []
                },
            },
        ],
        memberChannels: [
            [] as AnnouncementChannelApi[],
            {
                loadMemberChannels: async () => {
                    try {
                        return await announcementsChannelsList(String(values.currentTeam?.id))
                    } catch {
                        lemonToast.error('Failed to load Slack channels')
                        return values.memberChannels
                    }
                },
            },
        ],
        // Slack channel ids of the accounts matching the active filters. Reuses the
        // accounts query runner so the announcements filters behave exactly like the
        // accounts list (tags, relationships, search). Empty when no filter is active.
        filteredAccountChannelIds: [
            [] as string[],
            {
                loadFilteredAccountChannels: async (_, breakpoint) => {
                    if (!values.filtersActive) {
                        return []
                    }
                    const source: AccountsQuery = {
                        kind: NodeKind.AccountsQuery,
                        select: [`JSONExtractString(properties, 'slack_channel_id') AS ${SLACK_CHANNEL_COLUMN}`],
                        limit: ACCOUNT_MATCH_LIMIT,
                        tags: {
                            ...CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS,
                            name: 'customer_analytics_announcement_channels',
                        },
                    }
                    const search = values.accountSearch.trim()
                    if (search) {
                        source.search = search
                    }
                    if (values.accountTags.length > 0) {
                        source.tagNames = values.accountTags
                    }
                    if (values.allUnassigned) {
                        source.allRolesUnassigned = true
                    }
                    if (values.assignedTo.length > 0) {
                        source.assignedToUserIds = values.assignedTo
                    }
                    const response = await performQuery(source)
                    breakpoint()
                    const columnIndex = response.columns.indexOf(SLACK_CHANNEL_COLUMN)
                    if (columnIndex === -1) {
                        return []
                    }
                    const ids = new Set<string>()
                    for (const row of response.results) {
                        const channelId = row[columnIndex]
                        if (channelId) {
                            ids.add(String(channelId))
                        }
                    }
                    return [...ids]
                },
            },
        ],
    })),
    reducers({
        messageDraft: ['', { setMessage: (_state, { message }) => message }],
        selectedChannelIds: [[] as string[], { setSelectedChannelIds: (_state, { channelIds }) => channelIds }],
        submitting: [false, { setSubmitting: (_state, { submitting }) => submitting }],
        accountSearch: ['', { setAccountSearch: (_state, { search }) => search }],
        accountTags: [[] as string[], { setAccountTags: (_state, { tags }) => tags }],
        assignedTo: [[] as number[], { setAssignedTo: (_state, { userIds }) => userIds }],
        allUnassigned: [false, { setAllUnassigned: (_state, { value }) => value }],
    }),
    selectors({
        slackConnected: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): boolean =>
                !!currentTeam?.conversations_settings?.slack_enabled,
        ],
        currentUserId: [(s) => [s.user], (user: UserType | null): number | null => user?.id ?? null],
        filtersActive: [
            (s) => [s.accountSearch, s.accountTags, s.allUnassigned, s.assignedTo],
            (accountSearch: string, accountTags: string[], allUnassigned: boolean, assignedTo: number[]): boolean =>
                !!accountSearch.trim() || accountTags.length > 0 || allUnassigned || assignedTo.length > 0,
        ],
        assignedToCurrentUser: [
            (s) => [s.assignedTo, s.currentUserId],
            (assignedTo: number[], currentUserId: number | null): boolean =>
                currentUserId !== null && assignedTo.length === 1 && assignedTo[0] === currentUserId,
        ],
        // Member channels that belong to a filtered account — the preview list and the set
        // the "Select all" button applies. Intersecting with member channels drops accounts
        // whose channel the bot can't post to anyway.
        filteredChannels: [
            (s) => [s.memberChannels, s.filteredAccountChannelIds],
            (
                memberChannels: AnnouncementChannelApi[],
                filteredAccountChannelIds: string[]
            ): { key: string; label: string }[] => {
                const allowed = new Set(filteredAccountChannelIds)
                return memberChannels
                    .filter((channel) => allowed.has(channel.id))
                    .map((channel) => ({ key: channel.id, label: channelLabel(channel) }))
            },
        ],
        filteredChannelIds: [
            (s) => [s.filteredChannels],
            (filteredChannels: { key: string; label: string }[]): string[] =>
                filteredChannels.map((channel) => channel.key),
        ],
        channelOptions: [
            (s) => [s.memberChannels, s.filtersActive, s.filteredAccountChannelIds, s.selectedChannelIds],
            (
                memberChannels: AnnouncementChannelApi[],
                filtersActive: boolean,
                filteredAccountChannelIds: string[],
                selectedChannelIds: string[]
            ): { key: string; label: string }[] => {
                let channels = memberChannels
                if (filtersActive) {
                    // Keep already-selected channels visible so filtering never hides a
                    // pick the user can no longer remove.
                    const allowed = new Set(filteredAccountChannelIds)
                    const selected = new Set(selectedChannelIds)
                    channels = memberChannels.filter((channel) => allowed.has(channel.id) || selected.has(channel.id))
                }
                return channels.map((channel) => ({ key: channel.id, label: channelLabel(channel) }))
            },
        ],
        // Labels for the confirmation dialog. Falls back to the raw id so a channel the
        // picker no longer knows about still shows up in the list the user confirms.
        selectedChannelLabels: [
            (s) => [s.memberChannels, s.selectedChannelIds],
            (memberChannels: AnnouncementChannelApi[], selectedChannelIds: string[]): string[] => {
                const labelsById = new Map(memberChannels.map((channel) => [channel.id, channelLabel(channel)]))
                return selectedChannelIds.map((id) => labelsById.get(id) ?? id)
            },
        ],
        submitDisabledReason: [
            (s) => [s.messageDraft, s.selectedChannelIds, s.submitting],
            (messageDraft: string, selectedChannelIds: string[], submitting: boolean): string | undefined => {
                if (submitting) {
                    return 'Sending…'
                }
                if (!messageDraft.trim()) {
                    return 'Enter a message'
                }
                if (selectedChannelIds.length === 0) {
                    return 'Select at least one channel'
                }
                return undefined
            },
        ],
    }),
    listeners(({ values, actions }) => ({
        setAccountSearch: async (_, breakpoint) => {
            await breakpoint(ACCOUNT_SEARCH_DEBOUNCE_MS)
            actions.loadFilteredAccountChannels(null)
        },
        setAccountTags: () => actions.loadFilteredAccountChannels(null),
        setAssignedTo: ({ userIds }) => {
            if (userIds.length > 0 && values.allUnassigned) {
                actions.setAllUnassigned(false)
            }
            actions.loadFilteredAccountChannels(null)
        },
        setAllUnassigned: ({ value }) => {
            if (value && values.assignedTo.length > 0) {
                actions.setAssignedTo([])
            }
            actions.loadFilteredAccountChannels(null)
        },
        // "My accounts" is a shortcut for assigning the filter to the current user's id.
        setMyAccounts: ({ value }) => {
            actions.setAssignedTo(value && values.currentUserId !== null ? [values.currentUserId] : [])
        },
        clearAccountFilters: () => {
            actions.setAccountSearch('')
            actions.setAccountTags([])
            actions.setAssignedTo([])
            actions.setAllUnassigned(false)
        },
        selectAllFilteredChannels: () => {
            actions.setSelectedChannelIds([...new Set([...values.selectedChannelIds, ...values.filteredChannelIds])])
        },
        toggleChannel: ({ channelId }) => {
            const selected = values.selectedChannelIds
            actions.setSelectedChannelIds(
                selected.includes(channelId) ? selected.filter((id) => id !== channelId) : [...selected, channelId]
            )
        },
        submitAnnouncement: async () => {
            // Guard against double-submission while a send is in flight.
            if (values.submitting || values.submitDisabledReason) {
                return
            }
            actions.setSubmitting(true)
            try {
                await announcementsCreate(String(values.currentTeam?.id), {
                    message: values.messageDraft.trim(),
                    channels: values.selectedChannelIds,
                })
                lemonToast.success('Announcement sent')
                actions.setMessage('')
                actions.setSelectedChannelIds([])
                actions.loadAnnouncements()
            } catch {
                lemonToast.error('Failed to send announcement')
            } finally {
                actions.setSubmitting(false)
            }
        },
        // On a hard load the team (and so slackConnected) can resolve after this logic mounts,
        // so the afterMount check alone would skip the fetch and leave the picker empty. Load
        // once the team arrives connected too; the guard keeps it from double-fetching.
        loadCurrentTeamSuccess: () => {
            if (values.slackConnected && values.memberChannels.length === 0 && !values.memberChannelsLoading) {
                actions.loadMemberChannels()
            }
        },
    })),
    afterMount(({ values, actions }) => {
        actions.loadAnnouncements()
        if (values.slackConnected) {
            actions.loadMemberChannels()
        }
    }),
])
