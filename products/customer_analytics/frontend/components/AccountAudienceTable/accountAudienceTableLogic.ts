export const accountAudienceTableLogic = kea<accountAudienceTableLogicType>([
    path((key) => ['products', 'customerAnalytics', 'accountAudienceTable', 'accountAudienceTableLogic', key]),
    props({} as AccountAudienceTableLogicProps),
    key(({ scope }) => scope),
    connect(({ scope }: AccountAudienceTableLogicProps) => ({
        values: [
            accountsColumnConfigLogic({ scope }),
            ['querySelectColumns', 'visibleColumnNames', 'aliasToDefinition', 'relationshipDefinitionsLoaded'],
            userLogic,
            ['user'],
        ],
        actions: [membersLogic, ['ensureAllMembersLoaded']],
    })),
    actions({
        setSearchInput: (search: string) => ({ search }),
        setSearchQuery: (search: string) => ({ search }),
        setTagsFilter: (tags: string[]) => ({ tags }),
        setAssignmentStatus: (status: AssignmentStatus) => ({ status }),
        setAssignedToFilter: (userIds: number[]) => ({ userIds }),
        setAssignedToCurrentUser: (assignedToCurrentUser: boolean) => ({ assignedToCurrentUser }),
        reportFilterChange: (filterType: AccountAudienceFilterType) => ({ filterType }),
        toggleSort: (column: string) => ({ column }),
        reportAccountOpened: true,
    }),
    reducers({
        searchInput: ['', { setSearchInput: (_, { search }) => search }],
        searchQuery: ['', { setSearchQuery: (_, { search }) => search }],
        tagsFilter: [[] as string[], { setTagsFilter: (_, { tags }) => tags }],
        assignmentStatus: ['all' as AssignmentStatus, { setAssignmentStatus: (_, { status }) => status }],
        assignedToFilter: [
            [] as number[],
            {
                setAssignedToFilter: (_, { userIds }) => userIds,
                // Selected users only narrow assigned accounts.
                setAssignmentStatus: (userIds, { status }) => (status === 'assigned' ? userIds : []),
            },
        ],
        sortOrder: [
            null as AccountAudienceSortOrder,
            {
                toggleSort: (sortOrder, { column }) =>
                    sortOrder?.column !== column
                        ? { column, direction: 'asc' }
                        : sortOrder.direction === 'asc'
                          ? { column, direction: 'desc' }
                          : null,
            },
        ],
    }),
    selectors({
        currentUserId: [(s) => [s.user], (user: UserType | null): number | null => user?.id ?? null],
        assignedToCurrentUser: [
            (s) => [s.assignedToFilter, s.currentUserId],
            (assignedToFilter: number[], currentUserId: number | null): boolean =>
                currentUserId !== null && assignedToFilter.length === 1 && assignedToFilter[0] === currentUserId,
        ],
        tableDataNodeKey: [() => [(_, props) => props.scope], (scope: string): string => `account-audience-${scope}`],
        countDataNodeKey: [
            () => [(_, props) => props.scope],
            (scope: string): string => `account-audience-count-${scope}`,
        ],
        filteredAudienceQuery: [
            (s) => [
                (_, props) => props.audienceQuery,
                s.searchQuery,
                s.tagsFilter,
                s.assignmentStatus,
                s.assignedToFilter,
            ],
            (
                audienceQuery: AccountsQuery,
                searchQuery: string,
                tagsFilter: string[],
                assignmentStatus: AssignmentStatus,
                assignedToFilter: number[]
            ): AccountsQuery =>
                createAccountAudienceQuery(audienceQuery, {
                    searchQuery,
                    tagsFilter,
                    assignmentStatus,
                    assignedToFilter,
                }),
        ],
        // Null until relationship definitions settle, so the table fetches once with its final columns.
        tableQuerySource: [
            (s) => [
                s.filteredAudienceQuery,
                s.querySelectColumns,
                s.visibleColumnNames,
                s.aliasToDefinition,
                s.sortOrder,
                s.relationshipDefinitionsLoaded,
            ],
            (
                filteredAudienceQuery: AccountsQuery,
                querySelectColumns: string[],
                visibleColumnNames: string[],
                aliasToDefinition: Record<string, CustomPropertyDefinitionApi>,
                sortOrder: AccountAudienceSortOrder,
                relationshipDefinitionsLoaded: boolean
            ): AccountsQuery | null => {
                if (!relationshipDefinitionsLoaded) {
                    return null
                }
                // A removed column can't be sorted on, because its alias no longer resolves.
                const sortExpression =
                    sortOrder && visibleColumnNames.includes(sortOrder.column)
                        ? orderByExpression(sortOrder.column, aliasToDefinition)
                        : null
                return {
                    ...filteredAudienceQuery,
                    select: querySelectColumns,
                    orderBy: sortExpression
                        ? [sortOrder?.direction === 'desc' ? `${sortExpression} DESC` : sortExpression]
                        : undefined,
                }
            },
        ],
        tableQuery: [
            (s) => [s.tableQuerySource],
            (tableQuerySource: AccountsQuery | null): DataTableNode | null =>
                tableQuerySource
                    ? {
                          kind: NodeKind.DataTableNode,
                          source: tableQuerySource,
                          full: true,
                          // Hides DataTable's own sort indicator. The column headers render their own.
                          allowSorting: true,
                      }
                    : null,
        ],
        countQuery: [
            (s) => [s.filteredAudienceQuery],
            (filteredAudienceQuery: AccountsQuery): AccountsQuery => ({
                ...filteredAudienceQuery,
                metrics: ['count()'],
            }),
        ],
        hasTableFilters: [
            (s) => [s.searchQuery, s.tagsFilter, s.assignmentStatus],
            (searchQuery: string, tagsFilter: string[], assignmentStatus: AssignmentStatus): boolean =>
                searchQuery.trim() !== '' || tagsFilter.length > 0 || assignmentStatus !== 'all',
        ],
    }),
    listeners(({ actions, values, props }) => ({
        setSearchInput: async ({ search }, breakpoint) => {
            await breakpoint(ACCOUNT_AUDIENCE_SEARCH_DEBOUNCE_MS)
            actions.setSearchQuery(search)
            const trimmed = search.trim()
            posthog.capture(AccountsEvents.AudienceSearched, {
                source: props.source,
                query_length: trimmed.length,
                has_query: !!trimmed,
            })
        },
        setAssignedToFilter: ({ userIds }) => {
            if (userIds.length > 0 && values.assignmentStatus !== 'assigned') {
                actions.setAssignmentStatus('assigned')
            }
        },
        setAssignedToCurrentUser: ({ assignedToCurrentUser }) => {
            actions.setAssignedToFilter(
                assignedToCurrentUser && values.currentUserId !== null ? [values.currentUserId] : []
            )
        },
        reportFilterChange: ({ filterType }) => {
            posthog.capture(AccountsEvents.AudienceFilterChanged, {
                source: props.source,
                filter_type: filterType,
                tag_count: values.tagsFilter.length,
                assignment_status: values.assignmentStatus,
                assigned_to_count: values.assignedToFilter.length,
            })
        },
        toggleSort: () => {
            posthog.capture(AccountsEvents.AudienceSorted, {
                source: props.source,
                direction: values.sortOrder?.direction ?? null,
                is_custom_property: !!values.sortOrder && !!values.aliasToDefinition[values.sortOrder.column],
            })
        },
        reportAccountOpened: () => {
            posthog.capture(AccountsEvents.AudienceAccountOpened, { source: props.source })
        },
    })),
    afterMount(({ actions, props }) => {
        // Relationship cells show holder names, which come from the organization members.
        actions.ensureAllMembersLoaded()
        posthog.capture(AccountsEvents.AudienceViewed, { source: props.source })
    }),
])
