function shouldAutoApplySavedView(): boolean {
    const hasSharedView =
        typeof router.values.hashParams?.view === 'object' &&
        router.values.hashParams.view !== null &&
        !Array.isArray(router.values.hashParams.view)
    return (
        removeProjectIdIfPresent(router.values.location.pathname) === urls.customerAnalyticsAccounts() && !hasSharedView
    )
}

