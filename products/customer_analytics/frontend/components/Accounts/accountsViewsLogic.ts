function getInitialAccountsViewSelection(teamId: number, userId: string): AccountsViewSelection | null {
    const session = getAccountsViewSession(teamId, userId)
    const remembered = readAccountsViewSelection(teamId, userId) ?? readAccountsViewSelection(teamId)
    const id = session.initialized
        ? session.currentViewId
        : (session.reference ?? (session.allowRemembered ? (remembered?.id ?? null) : null))
    return id ? { id, name: remembered?.id === id ? remembered.name : null } : null
}

