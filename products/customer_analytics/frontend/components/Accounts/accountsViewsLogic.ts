export const accountsViewsLogic = kea<accountsViewsLogicType>([
    path(['scenes', 'customerAnalytics', 'accounts', 'accountsViewsLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            userLogic,
            ['user'],
            accountsLogic,
            ['viewState', 'draftRestored', 'viewStateHydrated'],
        ],
        actions: [accountsLogic, ['applyViewState', 'setAwaitingSavedView', 'syncViewStateToUrl']],
    })),
    actions({
        selectView: (id: string) => ({ id }),
        applyView: (view: ColumnConfigurationApi) => ({ view }),
        setCurrentViewId: (id: string | null) => ({ id }),
        setColumnWidth: (column: string, width: number) => ({ column, width }),
        reportColumnResize: true,
        setIsCreating: (isCreating: boolean) => ({ isCreating }),
        setViewToDelete: (id: string | null) => ({ id }),
        setViewToEdit: (id: string | null) => ({ id }),
        restoreSavedView: true,
    }),
    loaders(({ values }) => ({
        views: [
            [] as ColumnConfigurationApi[],
            {
                loadViews: async (): Promise<ColumnConfigurationApi[]> => {
                    const response = await columnConfigurationsList(String(values.currentTeamId), {
                        context_key: ACCOUNTS_COLUMN_CONFIG_KEY,
                    })
                    return response.results
                },
                updateView: async ({
                    id,
                    updates,
                }: {
                    id: string
                    updates: PatchedColumnConfigurationApi
                }): Promise<ColumnConfigurationApi[]> => {
                    const data =
                        Object.keys(updates).length === 0 ? serializeAccountsView(values.liveViewState) : updates
                    const response = await columnConfigurationsPartialUpdate(String(values.currentTeamId), id, data)
                    return values.views.map((view) => (view.id === id ? response : view))
                },
                deleteView: async ({ id }: { id: string }): Promise<ColumnConfigurationApi[]> => {
                    await columnConfigurationsDestroy(String(values.currentTeamId), id)
                    return values.views.filter((view) => view.id !== id)
                },
                patchViewProperties: async ({
                    id,
                    properties,
                }: {
                    id: string
                    properties: AccountsViewProperties
                }): Promise<ColumnConfigurationApi[]> => {
                    const response = await columnConfigurationsPartialUpdate(String(values.currentTeamId), id, {
                        properties,
                    })
                    return values.views.map((view) => (view.id === id ? response : view))
                },
            },
        ],
    })),
    reducers(() => ({
        currentViewId: [
            null as string | null,
            {
                persist: true,
                storageKey: `customerAnalytics.accounts.accountsViewsLogic.${getCurrentTeamId()}.currentViewId`,
            },
            {
                setCurrentViewId: (_, { id }) => id,
                deleteViewSuccess: (state, { views }) => (state && !views.find((v) => v.id === state) ? null : state),
            },
        ],
        columnWidths: [
            {} as AccountColumnWidthState,
            {
                persist: true,
                storageKey: `customerAnalytics.accounts.accountsViewsLogic.${getCurrentTeamId()}.columnWidths`,
            },
            {
                setColumnWidth: (state, { column, width }) => ({ ...state, [column]: width }),
            },
        ],
        isCreating: [
            false,
            {
                setIsCreating: (_, { isCreating }) => isCreating,
                submitViewFormSuccess: () => false,
            },
        ],
        viewToDelete: [
            null as string | null,
            {
                setViewToDelete: (_, { id }) => id,
                deleteViewSuccess: () => null,
            },
        ],
        viewToEdit: [
            null as string | null,
            {
                setViewToEdit: (_, { id }) => id,
                updateViewSuccess: (state, { payload }) =>
                    payload?.id === state && Object.keys(payload.updates).length > 0 ? null : state,
            },
        ],
    })),
    selectors({
        liveViewState: [(s) => [s.viewState], (viewState: AccountsViewState): AccountsViewState => viewState],
        currentView: [
            (s) => [s.views, s.currentViewId],
            (views: ColumnConfigurationApi[], currentViewId: string | null): ColumnConfigurationApi | null =>
                views.find((view) => view.id === currentViewId) ?? null,
        ],
        isDirty: [
            (s) => [s.currentView, s.liveViewState],
            (currentView: ColumnConfigurationApi | null, liveViewState: AccountsViewState): boolean =>
                currentView
                    ? !objectsEqual(
                          serializeAccountsView(deserializeAccountsView(currentView)),
                          serializeAccountsView(liveViewState)
                      )
                    : false,
        ],
        canEditCurrentView: [
            (s) => [s.currentView],
            (currentView: ColumnConfigurationApi | null): boolean => !!currentView,
        ],
    }),
    forms(({ actions, values }) => ({
        viewForm: {
            defaults: { name: '', visibility: 'private' as ViewVisibility },
            errors: ({ name }: { name: string }) => ({ name: !name?.trim() ? 'Name is required' : undefined }),
            submit: async ({ name, visibility }: { name: string; visibility: ViewVisibility }) => {
                if (values.viewToEdit) {
                    actions.updateView({ id: values.viewToEdit, updates: { name: name.trim(), visibility } })
                    return
                }
                const response = await columnConfigurationsCreate(String(values.currentTeamId), {
                    ...serializeAccountsView(values.liveViewState),
                    context_key: ACCOUNTS_COLUMN_CONFIG_KEY,
                    name: name.trim(),
                    visibility,
                })
                actions.loadViews()
                actions.applyView(response)
                actions.resetViewForm()
                posthog.capture(AccountsEvents.ViewSaved, { visibility }) // [PostHog] Event: dynamic event name
            },
        },
    })),
    listeners(({ actions, values }) => ({
        reportColumnResize: () => {
            posthog.capture(AccountsEvents.ColumnResized) // [PostHog] Event: dynamic event name
        },
        selectView: ({ id }) => {
            const view = values.views.find((v) => v.id === id)
            if (view) {
                actions.applyView(view)
            }
        },
        applyView: ({ view }) => {
            const state = deserializeAccountsView(view)
            actions.applyViewState(state, { source: 'saved_view', columns: 'restore' })
            actions.syncViewStateToUrl()
            actions.setCurrentViewId(view.id)
            posthog.capture(AccountsEvents.ViewSelected, { visibility: view.visibility }) // [PostHog] Event: dynamic event name
        },
        setViewToEdit: ({ id }) => {
            const view = id ? values.views.find((candidate) => candidate.id === id) : undefined
            if (view) {
                actions.setViewFormValues({ name: view.name ?? '', visibility: view.visibility ?? 'shared' })
            }
        },
        updateViewSuccess: ({ payload }) => {
            lemonToast.success('View updated')
            posthog.capture(AccountsEvents.ViewUpdated) // [PostHog] Event: dynamic event name
            if (payload && Object.keys(payload.updates).length > 0) {
                actions.resetViewForm()
            }
        },
        updateViewFailure: ({ error }) => {
            posthog.captureException(error)
            lemonToast.error('Failed to update view')
        },
        deleteViewSuccess: () => {
            lemonToast.success('View deleted')
            posthog.capture(AccountsEvents.ViewDeleted) // [PostHog] Event: dynamic event name
        },
        deleteViewFailure: ({ error }) => {
            posthog.captureException(error)
            lemonToast.error('Failed to delete view')
        },
        loadViewsFailure: ({ error }) => {
            posthog.captureException(error)
            lemonToast.error('Failed to load views')
            actions.setAwaitingSavedView(false)
        },
        submitViewFormFailure: ({ error }) => {
            posthog.captureException(error)
            lemonToast.error('Failed to save view')
        },
        patchViewPropertiesFailure: ({ error }) => {
            // Background migration failures report the exception without a toast.
            posthog.captureException(error)
        },
        [accountsLogic.actionTypes.setViewStateHydrated]: () => {
            actions.restoreSavedView()
        },
        loadViewsSuccess: () => {
            actions.restoreSavedView()
        },
        restoreSavedView: () => {
            if (!values.viewStateHydrated || values.viewsLoading) {
                return
            }

            let migratedView: ColumnConfigurationApi | null = null
            if (!values.draftRestored && !objectsEqual(values.liveViewState.tiles, DEFAULT_TILES)) {
                const candidate = values.views.find(
                    (view) =>
                        view.created_by === values.user?.id &&
                        !(view.properties as AccountsViewProperties | undefined)?.tiles?.length
                )
                if (candidate) {
                    actions.patchViewProperties({ id: candidate.id, properties: { tiles: values.liveViewState.tiles } })
                    // Use patched tiles because `views` still holds the stale row.
                    migratedView = { ...candidate, properties: { tiles: values.liveViewState.tiles } }
                }
            }

            if (values.currentViewId && !values.draftRestored && shouldAutoApplySavedView()) {
                const view =
                    migratedView?.id === values.currentViewId
                        ? migratedView
                        : values.views.find((v) => v.id === values.currentViewId)
                if (view) {
                    actions.applyView(view)
                }
            }
            actions.setAwaitingSavedView(false)
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.currentViewId && !values.draftRestored && shouldAutoApplySavedView()) {
            actions.setAwaitingSavedView(true)
        }
        actions.loadViews()
    }),
])
