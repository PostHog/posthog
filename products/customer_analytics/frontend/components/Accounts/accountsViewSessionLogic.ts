import { combineUrl, router } from 'kea-router'
import type { LocationChangedPayload } from 'kea-router/lib/types'

import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'
import { userLogic } from 'scenes/userLogic'

import type { UserType } from '~/types'

import type { AccountsViewState } from './accountsViewState'

export interface AccountsViewReturn {
    token: string
    url: string
    state: AccountsViewState | null
    viewId: string | null
    columnMode: 'defaults' | 'restore'
}

export interface AccountsViewSession {
    scope: string
    state: AccountsViewState | null
    columnMode: 'defaults' | 'restore'
    currentViewId: string | null
    reference: string | null | undefined
    initialized: boolean
    allowRemembered: boolean
    revision: number
    entryLocation: unknown
    returnView: AccountsViewReturn | null
}

