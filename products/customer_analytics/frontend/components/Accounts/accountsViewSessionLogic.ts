export type accountsViewSessionLogicType = MakeLogicType<
    accountsViewSessionLogicValues,
    {},
    Record<string, any>,
    accountsViewSessionLogicMeta
>

const accountsViewSessionLogic = kea<accountsViewSessionLogicType>([
    path(['scenes', 'customerAnalytics', 'accounts', 'accountsViewSessionLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId'], userLogic, ['user']] })),
    listeners(({ values, cache }) => ({
        [teamLogic.actionTypes.loadCurrentTeamSuccess]: () => {
            getAccountsViewSession(values.currentTeamId, values.user?.uuid ?? null)
        },
        [userLogic.actionTypes.loadUserSuccess]: () => {
            getAccountsViewSession(values.currentTeamId, values.user?.uuid ?? null)
        },
        [router.actionTypes.locationChanged]: ({ pathname }) => {
            const session = cache.session as AccountsViewSession | undefined
            const path = removeProjectIdIfPresent(pathname)
            if (
                !session ||
                path === urls.customerAnalyticsAccounts() ||
                path.startsWith(`${urls.customerAnalyticsAccounts()}/`)
            ) {
                return
            }
            session.state = null
            session.initialized = false
            session.returnView = null
            session.entryLocation = null
            session.reference = session.currentViewId
            session.revision++
        },
    })),
])

export function getAccountsViewSession(teamId: number | null, userId: string | null): AccountsViewSession {
    let logic = accountsViewSessionLogic.findMounted()
    if (!logic) {
        logic = accountsViewSessionLogic()
        // Identity changes must discard edits even when the Accounts scene is unmounted.
        // This owner stays mounted for the kea context's lifetime and never writes browser storage.
        logic.mount()
    }
    const scope = `${teamId}.${userId}`
    if (!logic.cache.session || logic.cache.session.scope !== scope) {
        logic.cache.session = {
            scope,
            state: null,
            columnMode: 'defaults',
            currentViewId: null,
            reference: undefined,
            initialized: false,
            allowRemembered: true,
            revision: 0,
            entryLocation: null,
            returnView: null,
        } satisfies AccountsViewSession
    }
    return logic.cache.session
}

export function getAccountsBackUrl(teamId: number | null, userId: string | null): string {
    if (teamId === null || userId === null) {
        return urls.customerAnalyticsAccounts()
    }
    const session = getAccountsViewSession(teamId, userId)
    return (
        session.returnView?.url ??
        combineUrl(urls.customerAnalyticsAccounts(), session.currentViewId ? { view: session.currentViewId } : {}).url
    )
}
