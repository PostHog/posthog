export const accountUsersTableLogic = kea<accountUsersTableLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountUsersTableLogic', key]),
    props({} as AccountUsersTableLogicProps),
    key((props) => `${props.accountId}:${props.instanceId ?? 'default'}`),
    connect(() => ({
        values: [teamLogic, ['currentTeam'], userLogic, ['user']],
    })),
    actions({
        setQuery: (query: DataTableNode) => ({ query }),
    }),
    loaders(({ props, values }) => ({
        memberships: [
            null as Record<string, AccountPersonMembershipsApi> | null,
            {
                loadMemberships: async (
                    { response, append }: { response: HogQLQueryResponse; append?: boolean },
                    breakpoint
                ) => {
                    const columnIndex = response.columns?.indexOf(MEMBERSHIP_COLUMN) ?? -1
                    if (columnIndex < 0 || !values.currentTeam) {
                        return values.memberships
                    }
                    const teamId = String(values.currentTeam.id)
                    const memberships: Record<string, AccountPersonMembershipsApi> = append
                        ? { ...values.memberships }
                        : {}
                    const personIds = [...new Set((response.results ?? []).map((row) => row[columnIndex]))].filter(
                        (id): id is string => typeof id === 'string' && !Object.hasOwn(memberships, id)
                    )
                    await breakpoint(0)
                    try {
                        for (let offset = 0; offset < personIds.length; offset += 500) {
                            const result = await api.accountsPersonsMembershipsCreate(teamId, props.accountId, {
                                person_ids: personIds.slice(offset, offset + 500),
                            })
                            breakpoint()
                            for (const item of result) {
                                memberships[item.person_id] = item
                            }
                        }
                        return {
                            ...Object.fromEntries(
                                personIds.map((personId) => [personId, { person_id: personId, accounts: [] }])
                            ),
                            ...memberships,
                        }
                    } catch (error) {
                        breakpoint()
                        posthog.captureException(error, { scope: 'accountUsersTableLogic.loadMemberships' })
                        return append ? values.memberships : null
                    }
                },
            },
        ],
    })),
    reducers(({ props }) => ({
        savedQuery: [parseSavedQuery(props.initialConfig), { setQuery: (_, { query }) => createSavedQuery(query) }],
    })),
    selectors(({ props }) => ({
        query: [
            (s) => [s.savedQuery, s.currentTeam, s.user],
            (
                savedQuery: DataTableNode | null,
                currentTeam: TeamPublicType | TeamType | null,
                user: UserType | null
            ): DataTableNode => {
                const defaultColumns = createDefaultColumns(
                    currentTeam?.extra_settings?.person_last_seen_at_enabled === true
                )
                const query = savedQuery ?? createDefaultQuery(defaultColumns)
                const actorsQuery = query.source as ActorsQuery
                const select = actorsQuery.select ?? []
                return {
                    ...query,
                    defaultColumns,
                    hiddenColumns: [
                        ...(query.hiddenColumns ?? []).filter((column) => column !== MEMBERSHIP_COLUMN),
                        MEMBERSHIP_COLUMN,
                    ],
                    source: {
                        ...actorsQuery,
                        select: select.some(isHogQLAggregation)
                            ? select
                            : [...(user?.is_staff ? createStaffSelect(select) : select), MEMBERSHIP_COLUMN],
                        source: { kind: NodeKind.AccountUsersQuery, accountId: props.accountId },
                    },
                }
            },
        ],
        // A separate download query turns off downloads in the selected-columns dialog, so override only when needed.
        exportQuery: [
            (s) => [s.query],
            (query: DataTableNode): DataTableNode | undefined =>
                (query.source as ActorsQuery).select?.some(
                    (column) => column === IMPERSONATE_COLUMN || column === MEMBERSHIP_COLUMN
                )
                    ? filterTableOnlyColumns(query)
                    : undefined,
        ],
    })),
    listeners(({ props, values, actions }) => ({
        [dataNodeLogic({
            key: `account-users-${props.accountId}-${props.instanceId ?? 'default'}`,
            query: { kind: NodeKind.ActorsQuery },
        }).actionTypes.loadDataSuccess]: ({ response }) => {
            if (response?.results) {
                actions.loadMemberships({ response })
            }
        },
        [dataNodeLogic({
            key: `account-users-${props.accountId}-${props.instanceId ?? 'default'}`,
            query: { kind: NodeKind.ActorsQuery },
        }).actionTypes.loadNextDataSuccess]: ({ response }) => {
            if (response?.results) {
                actions.loadMemberships({ response, append: true })
            }
        },
        [dataNodeLogic({
            key: `account-users-${props.accountId}-${props.instanceId ?? 'default'}`,
            query: { kind: NodeKind.ActorsQuery },
        }).actionTypes.loadNewDataSuccess]: ({ response }) => {
            if (response?.results) {
                actions.loadMemberships({ response })
            }
        },
        setQuery: () => {
            if (values.savedQuery) {
                props.onConfigChange?.({ query: values.savedQuery })
            }
            posthog.capture(AccountsEvents.RelatedUsersTableChanged)
        },
    })),
])
