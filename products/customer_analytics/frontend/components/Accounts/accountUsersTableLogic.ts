import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'

import { ActorsQuery, DataTableNode, NodeKind } from '~/queries/schema/schema-general'
import { TeamPublicType, TeamType } from '~/types'

import { CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS } from '../../constants'
import { getTileRecord, type AccountViewTileConfig, type AccountViewTileLogicProps } from './accountViewTileConfig'
import { AccountsEvents } from './constants'

export interface AccountUsersTableLogicProps extends AccountViewTileLogicProps {
    accountId: string
}

function createDefaultColumns(lastSeenEnabled: boolean): string[] {
    return [
        'person_display_name -- Person',
        'properties.current_organization_membership_level_name -- Access level',
        ...(lastSeenEnabled ? ['last_seen_at -- Last seen'] : []),
    ]
}

function createDefaultQuery(defaultColumns: string[]): DataTableNode {
    return {
        kind: NodeKind.DataTableNode,
        full: true,
        showOpenEditorButton: false,
        showTimings: false,
        hiddenColumns: ['id', 'person.$delete'],
        source: {
            kind: NodeKind.ActorsQuery,
            select: defaultColumns,
            tags: CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS,
        },
    }
}

function parseSavedQuery(config: AccountViewTileConfig | undefined): DataTableNode | null {
    const saved = getTileRecord(config, 'query') as DataTableNode | null
    return saved?.kind === NodeKind.DataTableNode && saved.source?.kind === NodeKind.ActorsQuery ? saved : null
}

// Account views are reusable across accounts, so the saved query never pins an account. Default
// columns follow the team's settings at read time, so saving them would freeze stale defaults.
function createSavedQuery(query: DataTableNode): DataTableNode {
    const { defaultColumns: _defaultColumns, ...table } = query
    const { source: _accountSource, ...actorsQuery } = table.source as ActorsQuery
    return { ...table, source: actorsQuery }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountUsersTableLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    query: DataTableNode
    savedQuery: DataTableNode | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountUsersTableLogicActions {
    setQuery: (query: DataTableNode) => {
        query: DataTableNode
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountUsersTableLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        query: (savedQuery: DataTableNode | null, currentTeam: TeamPublicType | TeamType | null) => DataTableNode
    }
}

export type accountUsersTableLogicType = MakeLogicType<
    accountUsersTableLogicValues,
    accountUsersTableLogicActions,
    AccountUsersTableLogicProps,
    accountUsersTableLogicMeta
>

export const accountUsersTableLogic = kea<accountUsersTableLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountUsersTableLogic', key]),
    props({} as AccountUsersTableLogicProps),
    key((props) => `${props.accountId}:${props.instanceId ?? 'default'}`),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
    })),
    actions({
        setQuery: (query: DataTableNode) => ({ query }),
    }),
    reducers(({ props }) => ({
        savedQuery: [parseSavedQuery(props.initialConfig), { setQuery: (_, { query }) => createSavedQuery(query) }],
    })),
    selectors(({ props }) => ({
        query: [
            (s) => [s.savedQuery, s.currentTeam],
            (savedQuery: DataTableNode | null, currentTeam: TeamPublicType | TeamType | null): DataTableNode => {
                const defaultColumns = createDefaultColumns(
                    currentTeam?.extra_settings?.person_last_seen_at_enabled === true
                )
                const query = savedQuery ?? createDefaultQuery(defaultColumns)
                return {
                    ...query,
                    defaultColumns,
                    source: {
                        ...(query.source as ActorsQuery),
                        source: { kind: NodeKind.AccountUsersQuery, accountId: props.accountId },
                    },
                }
            },
        ],
    })),
    listeners(({ props, values }) => ({
        setQuery: () => {
            if (values.savedQuery) {
                props.onConfigChange?.({ query: values.savedQuery })
            }
            posthog.capture(AccountsEvents.RelatedUsersTableChanged)
        },
    })),
])
