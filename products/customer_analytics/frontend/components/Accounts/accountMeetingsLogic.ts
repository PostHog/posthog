import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import {
    accountsMeetingsList,
    accountsPartialUpdate,
    accountsRetrieve,
} from 'products/customer_analytics/frontend/generated/api'
import type {
    AccountApi,
    MeetingApi,
    PatchedAccountApiProperties,
} from 'products/customer_analytics/frontend/generated/api.schemas'

import { accountLinksLogic } from './accountLinksLogic'
import { AccountsEvents } from './constants'

export interface AccountMeetingsLogicProps {
    accountId: string
}

export interface AccountMeetingsResult {
    meetings: MeetingApi[] | null
    loadFailed?: boolean
}

// The view compares against this by reference to tell "not loaded yet" from a loaded empty result.
export const NOT_LOADED: AccountMeetingsResult = { meetings: null }

function cleanEmails(values: string[]): string[] {
    return Array.from(new Set(values.map((value) => value.trim().toLowerCase()).filter(Boolean)))
}

function cleanDomains(values: string[]): string[] {
    return cleanEmails(values.map((value) => value.replace(/^@/, '')))
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountMeetingsLogicValues {
    account: AccountApi | null // accountLinksLogic
    currentTeamId: number | null // teamLogic
    domainsDraft: string[]
    emailsDraft: string[]
    matchingEditorOpen: boolean
    meetingsResult: AccountMeetingsResult
    meetingsResultLoading: boolean
    savingMatching: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountMeetingsLogicActions {
    loadAccountSuccess: (
        account: AccountApi | null,
        payload?: any
    ) => {
        account: AccountApi | null
        payload?: any
    } // accountLinksLogic
    closeMatchingEditor: () => {
        value: true
    }
    loadMeetings: () => any
    loadMeetingsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadMeetingsSuccess: (
        meetingsResult: AccountMeetingsResult,
        payload?: any
    ) => {
        meetingsResult: AccountMeetingsResult
        payload?: any
    }
    openMatchingEditor: () => {
        value: true
    }
    saveMatching: () => {
        value: true
    }
    saveMatchingFinished: () => {
        value: true
    }
    saveMatchingStarted: () => {
        value: true
    }
    setDomainsDraft: (domains: string[]) => {
        domains: string[]
    }
    setEmailsDraft: (emails: string[]) => {
        emails: string[]
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountMeetingsLogicMeta {
    key: string
}

export type accountMeetingsLogicType = MakeLogicType<
    accountMeetingsLogicValues,
    accountMeetingsLogicActions,
    AccountMeetingsLogicProps,
    accountMeetingsLogicMeta
>

export const accountMeetingsLogic = kea<accountMeetingsLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountMeetingsLogic', key]),
    props({} as AccountMeetingsLogicProps),
    key((props) => props.accountId),
    connect((props: AccountMeetingsLogicProps) => ({
        values: [teamLogic, ['currentTeamId'], accountLinksLogic({ accountId: props.accountId }), ['account']],
        actions: [accountLinksLogic({ accountId: props.accountId }), ['loadAccountSuccess']],
    })),
    actions({
        openMatchingEditor: true,
        closeMatchingEditor: true,
        setDomainsDraft: (domains: string[]) => ({ domains }),
        setEmailsDraft: (emails: string[]) => ({ emails }),
        saveMatching: true,
        saveMatchingStarted: true,
        saveMatchingFinished: true,
    }),
    loaders(({ props, values }) => ({
        meetingsResult: [
            NOT_LOADED,
            {
                loadMeetings: async (): Promise<AccountMeetingsResult> => {
                    try {
                        const meetings = await accountsMeetingsList(String(values.currentTeamId), props.accountId)
                        return { meetings }
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountMeetingsLogic.loadMeetings',
                        })
                        return { meetings: null, loadFailed: true }
                    }
                },
            },
        ],
    })),
    reducers({
        matchingEditorOpen: [
            false,
            {
                openMatchingEditor: () => true,
                closeMatchingEditor: () => false,
            },
        ],
        domainsDraft: [
            [] as string[],
            {
                setDomainsDraft: (_, { domains }) => domains,
            },
        ],
        emailsDraft: [
            [] as string[],
            {
                setEmailsDraft: (_, { emails }) => emails,
            },
        ],
        savingMatching: [
            false,
            {
                saveMatchingStarted: () => true,
                saveMatchingFinished: () => false,
            },
        ],
    }),
    listeners(({ actions, values, props }) => ({
        openMatchingEditor: () => {
            actions.setDomainsDraft(values.account?.properties?.email_domains ?? [])
            actions.setEmailsDraft(values.account?.properties?.known_emails ?? [])
        },
        saveMatching: async () => {
            if (values.savingMatching) {
                return
            }
            const projectId = String(values.currentTeamId)
            const domains = cleanDomains(values.domainsDraft)
            const emails = cleanEmails(values.emailsDraft)
            actions.saveMatchingStarted()
            try {
                const current = await accountsRetrieve(projectId, props.accountId)
                const updated = await accountsPartialUpdate(projectId, props.accountId, {
                    properties: {
                        ...current.properties,
                        email_domains: domains,
                        known_emails: emails,
                    } as PatchedAccountApiProperties,
                })
                actions.loadAccountSuccess(updated)
                actions.closeMatchingEditor()
                lemonToast.success('Meeting matching updated')
                posthog.capture(AccountsEvents.MeetingMatchingSaved, {
                    domain_count: domains.length,
                    email_count: emails.length,
                })
            } catch (error) {
                posthog.captureException(error as Error, { scope: 'accountMeetingsLogic.saveMatching' })
                lemonToast.error('Failed to save meeting matching')
            } finally {
                actions.saveMatchingFinished()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadMeetings()
    }),
])
