export const accountFeatureRequestsLogic = kea<accountFeatureRequestsLogicType>([
    props({} as AccountFeatureRequestsLogicProps),
    key((props) => props.accountId),
    path((key) => ['products', 'customerAnalytics', 'accountFeatureRequestsLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentTeam']] })),
    actions({
        openRequestPicker: true,
        closeRequestPicker: true,
        setSelectedRequestId: (selectedRequestId: string | null) => ({ selectedRequestId }),
        setAccountRequestsPage: (page: number) => ({ page }),
        setAccountRequestsSearch: (search: string) => ({ search }),
        setRequestSearch: (search: string) => ({ search }),
        linkSelectedRequest: true,
        setLinkingRequest: (linkingRequest: boolean) => ({ linkingRequest }),
    }),
    loaders(({ props, values }) => ({
        accountRequests: [
            EMPTY_REQUESTS_RESPONSE,
            {
                loadAccountRequests: async (_ = null, breakpoint) => {
                    const response = await featureRequestsList(String(values.currentTeam?.id), {
                        account_ids: [props.accountId],
                        archive_state: 'all',
                        search: values.accountRequestsSearch.trim() || undefined,
                        limit: ACCOUNT_FEATURE_REQUESTS_PAGE_SIZE,
                        offset: (values.accountRequestsPage - 1) * ACCOUNT_FEATURE_REQUESTS_PAGE_SIZE,
                    })
                    breakpoint()
                    return response
                },
            },
        ],
        availableRequests: [
            [] as FeatureRequestApi[],
            {
                loadAvailableRequests: async () => {
                    const response = await featureRequestsList(String(values.currentTeam?.id), {
                        archive_state: 'active',
                        limit: AVAILABLE_REQUESTS_LIMIT,
                        offset: 0,
                        search: values.requestSearch.trim() || undefined,
                    })
                    return response.results.filter(
                        (request) =>
                            request.can_update &&
                            !request.account_links.some((link) => link.account.id === props.accountId)
                    )
                },
            },
        ],
    })),
    reducers({
        requestPickerOpen: [false, { openRequestPicker: () => true, closeRequestPicker: () => false }],
        selectedRequestId: [
            null as string | null,
            {
                setSelectedRequestId: (_, { selectedRequestId }) => selectedRequestId,
                setRequestSearch: () => null,
                openRequestPicker: () => null,
                closeRequestPicker: () => null,
            },
        ],
        accountRequestsPage: [
            1,
            {
                setAccountRequestsPage: (_, { page }) => page,
                setAccountRequestsSearch: () => 1,
            },
        ],
        accountRequestsSearch: ['', { setAccountRequestsSearch: (_, { search }) => search }],
        requestSearch: [
            '',
            {
                setRequestSearch: (_, { search }) => search,
                openRequestPicker: () => '',
                closeRequestPicker: () => '',
            },
        ],
        linkingRequest: [false, { setLinkingRequest: (_, { linkingRequest }) => linkingRequest }],
        accountRequestsError: [
            null as string | null,
            {
                loadAccountRequests: () => null,
                loadAccountRequestsSuccess: () => null,
                loadAccountRequestsFailure: () => "Couldn't load feature requests.",
            },
        ],
        availableRequestsError: [
            null as string | null,
            {
                loadAvailableRequests: () => null,
                loadAvailableRequestsSuccess: () => null,
                loadAvailableRequestsFailure: () => "Couldn't load available feature requests.",
                closeRequestPicker: () => null,
            },
        ],
    }),
    selectors({
        candidateOptions: [
            (selectors) => [selectors.availableRequests],
            (requests: FeatureRequestApi[]): { key: string; label: string }[] =>
                requests.map((request) => ({ key: request.id, label: request.title })),
        ],
    }),
    listeners(({ props, values, actions }) => ({
        openRequestPicker: () => actions.loadAvailableRequests(),
        setAccountRequestsPage: () => actions.loadAccountRequests(),
        setAccountRequestsSearch: async (_, breakpoint) => {
            await breakpoint(300)
            actions.loadAccountRequests()
        },
        setRequestSearch: async (_, breakpoint) => {
            await breakpoint(300)
            actions.loadAvailableRequests()
        },
        linkSelectedRequest: async () => {
            if (!values.selectedRequestId || values.linkingRequest) {
                return
            }
            const request = values.availableRequests.find((item) => item.id === values.selectedRequestId)
            if (!request) {
                return
            }
            actions.setLinkingRequest(true)
            try {
                await featureRequestsUpdate(String(values.currentTeam?.id), request.id, {
                    expected_version: request.version,
                    account_ids: [...request.account_links.map((link) => link.account.id), props.accountId],
                })
                actions.closeRequestPicker()
                actions.loadAccountRequests()
                lemonToast.success('Feature request linked')
            } catch (error) {
                if (error instanceof ApiError && error.status === 409) {
                    actions.setSelectedRequestId(null)
                    actions.loadAvailableRequests()
                    lemonToast.error('This request changed. Select it again to retry.')
                } else {
                    lemonToast.error("Couldn't link the feature request.")
                }
            } finally {
                actions.setLinkingRequest(false)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadAccountRequests()
    }),
])
