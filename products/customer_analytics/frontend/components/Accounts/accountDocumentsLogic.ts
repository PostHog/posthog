export interface AccountDocumentsLogicProps {
    accountId: string
    instanceId?: string
}

export interface AccountDocumentsResult {
    documents: AccountDocumentApi[] | null
    loadFailed?: boolean
}

export interface AccountLegalDocumentsResult {
    documents: AccountLegalDocumentApi[] | null
    loadFailed?: boolean
}

// The view compares against these by reference to tell "not loaded yet" from a loaded empty result.
export const NOT_LOADED: AccountDocumentsResult = { documents: null }
export const LEGAL_NOT_LOADED: AccountLegalDocumentsResult = { documents: null }

export type AccountDocumentRow =
    | { kind: 'account'; id: string; createdAt: string; document: AccountDocumentApi }
    | { kind: 'legal'; id: string; createdAt: string; document: AccountLegalDocumentApi }

export type AccountDocumentOpenedVia = 'preview' | 'pandadoc' | 'link' | 'legal_download'

export interface AccountDocumentFormValues {
    source: AccountDocumentSource
    url: string
    title: string
    document_type: AccountDocumentType
    status: AccountDocumentStatus
    effective_date: string | null
    end_date: string | null
    amount: string
}

export const EMPTY_DOCUMENT_FORM: AccountDocumentFormValues = {
    source: 'pandadoc',
    url: '',
    title: '',
    document_type: 'order_form',
    status: 'draft',
    effective_date: null,
    end_date: null,
    amount: '',
}

function formValuesFor(document: AccountDocumentApi): AccountDocumentFormValues {
    return {
        source: document.source,
        url: document.source === 'pandadoc' ? document.pandadoc_document_id : document.external_url,
        title: document.title,
        document_type: document.document_type,
        status: document.status,
        effective_date: document.effective_date ?? null,
        end_date: document.end_date ?? null,
        amount: document.amount ?? '',
    }
}

function writeBodyFor(values: AccountDocumentFormValues): AccountDocumentWriteApi {
    return {
        source: values.source,
        url: values.url.trim(),
        title: values.title.trim(),
        document_type: values.document_type,
        status: values.status,
        effective_date: values.effective_date,
        end_date: values.end_date,
        amount: values.amount.trim() === '' ? null : values.amount.trim(),
    }
}

