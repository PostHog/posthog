export const accountDocumentsLogic = kea<accountDocumentsLogicType>([
    props({} as AccountDocumentsLogicProps),
    key((props) => `${props.accountId}:${props.instanceId ?? 'default'}`),
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountDocumentsLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        loadAll: true,
        openEditor: (document: AccountDocumentApi | null = null) => ({ document }),
        closeEditor: true,
        openPreview: (document: AccountDocumentApi) => ({ document }),
        closePreview: true,
        syncDocument: (document: AccountDocumentApi) => ({ document }),
        syncDocumentFailure: (document: AccountDocumentApi) => ({ document }),
        deleteDocument: (document: AccountDocumentApi) => ({ document }),
        deleteDocumentSuccess: (document: AccountDocumentApi) => ({ document }),
        deleteDocumentFailure: (document: AccountDocumentApi) => ({ document }),
        replaceDocument: (document: AccountDocumentApi) => ({ document }),
        reportDocumentOpened: (
            document: AccountDocumentApi | AccountLegalDocumentApi,
            via: AccountDocumentOpenedVia
        ) => ({
            document,
            via,
        }),
    }),
    loaders(({ props, values }) => ({
        documentsResult: [
            NOT_LOADED,
            {
                loadDocuments: async (): Promise<AccountDocumentsResult> => {
                    try {
                        const documents = await accountsDocumentsList(String(values.currentTeamId), props.accountId)
                        return { documents }
                    } catch (error) {
                        posthog.captureException(error as Error, { scope: 'accountDocumentsLogic.loadDocuments' })
                        return { documents: null, loadFailed: true }
                    }
                },
            },
        ],
        legalResult: [
            LEGAL_NOT_LOADED,
            {
                loadLegalDocuments: async (): Promise<AccountLegalDocumentsResult> => {
                    try {
                        const documents = await accountsDocumentsLegalList(
                            String(values.currentTeamId),
                            props.accountId
                        )
                        return { documents }
                    } catch (error) {
                        posthog.captureException(error as Error, { scope: 'accountDocumentsLogic.loadLegalDocuments' })
                        return { documents: null, loadFailed: true }
                    }
                },
            },
        ],
    })),
    forms(({ actions, props, values }) => ({
        documentForm: {
            defaults: EMPTY_DOCUMENT_FORM,
            errors: ({ source, url, title, amount }: AccountDocumentFormValues) => ({
                url: !url.trim()
                    ? source === 'pandadoc'
                        ? 'Paste the PandaDoc document link'
                        : 'Enter a link to the document'
                    : undefined,
                title: source === 'link' && !title.trim() ? 'Enter a title' : undefined,
                amount: amount.trim() && Number.isNaN(Number(amount.trim())) ? 'Enter a number' : undefined,
            }),
            submit: async (formValues: AccountDocumentFormValues) => {
                const body = writeBodyFor(formValues)
                const editing = values.editingDocument
                const saved = editing
                    ? await accountsDocumentsPartialUpdate(
                          String(values.currentTeamId),
                          props.accountId,
                          editing.id,
                          body
                      )
                    : await accountsDocumentsCreate(String(values.currentTeamId), props.accountId, body)
                posthog.capture(AccountsEvents.DocumentSaved, {
                    is_new: !editing,
                    source: saved.source,
                    document_type: saved.document_type,
                    status: saved.status,
                })
                actions.closeEditor()
                actions.loadDocuments()
                lemonToast.success(editing ? 'Document updated' : 'Document added')
            },
        },
    })),
    reducers({
        editorOpen: [
            false,
            {
                openEditor: () => true,
                closeEditor: () => false,
            },
        ],
        editingDocument: [
            null as AccountDocumentApi | null,
            {
                openEditor: (_, { document }) => document,
                closeEditor: () => null,
            },
        ],
        previewDocument: [
            null as AccountDocumentApi | null,
            {
                openPreview: (_, { document }) => document,
                closePreview: () => null,
            },
        ],
        syncingDocumentId: [
            null as string | null,
            {
                syncDocument: (_, { document }) => document.id,
                replaceDocument: () => null,
                syncDocumentFailure: () => null,
            },
        ],
        deletingDocumentId: [
            null as string | null,
            {
                deleteDocument: (_, { document }) => document.id,
                deleteDocumentSuccess: () => null,
                deleteDocumentFailure: () => null,
            },
        ],
        documentsResult: {
            replaceDocument: (state, { document }) => ({
                ...state,
                documents:
                    state.documents?.map((existing) => (existing.id === document.id ? document : existing)) ?? null,
            }),
            deleteDocumentSuccess: (state, { document }) => ({
                ...state,
                documents: state.documents?.filter((existing) => existing.id !== document.id) ?? null,
            }),
        },
    }),
    selectors({
        rows: [
            (s) => [s.documentsResult, s.legalResult],
            (
                documentsResult: AccountDocumentsResult,
                legalResult: AccountLegalDocumentsResult
            ): AccountDocumentRow[] => {
                const accountRows: AccountDocumentRow[] = (documentsResult.documents ?? []).map((document) => ({
                    kind: 'account',
                    id: document.id,
                    createdAt: document.created_at,
                    document,
                }))
                const legalRows: AccountDocumentRow[] = (legalResult.documents ?? []).map((document) => ({
                    kind: 'legal',
                    id: document.id,
                    createdAt: document.created_at,
                    document,
                }))
                return [...accountRows, ...legalRows].sort((a, b) => b.createdAt.localeCompare(a.createdAt))
            },
        ],
        previewUrl: [
            (s) => [s.currentTeamId, (_, p) => p.accountId],
            (currentTeamId: number | null, accountId) =>
                (document: AccountDocumentApi): string =>
                    getAccountsDocumentsPreviewRetrieveUrl(String(currentTeamId), accountId, document.id),
        ],
        legalDownloadUrl: [
            (s) => [s.currentTeamId, (_, p) => p.accountId],
            (currentTeamId: number | null, accountId) =>
                (document: AccountLegalDocumentApi): string =>
                    getAccountsDocumentsLegalDownloadRetrieveUrl(String(currentTeamId), accountId, document.id),
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadAll: () => {
            actions.loadDocuments()
            actions.loadLegalDocuments()
        },
        openEditor: ({ document }) => {
            actions.resetDocumentForm(document ? formValuesFor(document) : EMPTY_DOCUMENT_FORM)
            posthog.capture(AccountsEvents.DocumentEditorOpened, { is_new: !document })
        },
        openPreview: ({ document }) => {
            actions.reportDocumentOpened(document, 'preview')
        },
        syncDocument: async ({ document }) => {
            try {
                const synced = await accountsDocumentsSyncCreate(
                    String(values.currentTeamId),
                    props.accountId,
                    document.id
                )
                actions.replaceDocument(synced)
                posthog.capture(AccountsEvents.DocumentSynced, { status: synced.status })
            } catch (error) {
                actions.syncDocumentFailure(document)
                posthog.captureException(error as Error, { scope: 'accountDocumentsLogic.syncDocument' })
                lemonToast.error("Couldn't refresh this document from PandaDoc. Try again in a moment.")
            }
        },
        deleteDocument: async ({ document }) => {
            try {
                await accountsDocumentsDestroy(String(values.currentTeamId), props.accountId, document.id)
                actions.deleteDocumentSuccess(document)
                posthog.capture(AccountsEvents.DocumentDeleted, {
                    source: document.source,
                    document_type: document.document_type,
                })
                lemonToast.success('Document removed')
            } catch (error) {
                actions.deleteDocumentFailure(document)
                posthog.captureException(error as Error, { scope: 'accountDocumentsLogic.deleteDocument' })
                lemonToast.error("Couldn't remove this document. Try again.")
            }
        },
        reportDocumentOpened: ({ document, via }) => {
            posthog.capture(AccountsEvents.DocumentOpened, {
                via,
                document_type: document.document_type,
                source: 'source' in document ? document.source : 'legal',
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadAll()
    }),
])
