export interface accountProductUsagePeopleLogicValues {
    currentTeamId: number | null // teamLogic
    details: ProductUsageDetails | null
    detailsLoading: boolean
    error: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountProductUsagePeopleLogicActions {
    loadDetails: (_: void) => void
    loadDetailsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadDetailsSuccess: (
        details: {
            firsts: BookActivityFirstsResult | null
            people: BookActivityPeopleResult
        } | null,
        payload?: void
    ) => {
        details: {
            firsts: BookActivityFirstsResult | null
            people: BookActivityPeopleResult
        } | null
        payload?: void
    }
}

