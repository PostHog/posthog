export interface accountProductUsagePeopleLogicMeta {
    key: string
}

export type accountProductUsagePeopleLogicType = MakeLogicType<
    accountProductUsagePeopleLogicValues,
    accountProductUsagePeopleLogicActions,
    AccountProductUsagePeopleLogicProps,
    accountProductUsagePeopleLogicMeta
>

export const accountProductUsagePeopleLogic: LogicWrapper<accountProductUsagePeopleLogicType> =
    kea<accountProductUsagePeopleLogicType>([
        props({} as AccountProductUsagePeopleLogicProps),
        key((props) => props.instanceId),
        path((key) => ['products', 'customer_analytics', 'accountProductUsagePeopleLogic', key]),
        connect({ values: [teamLogic, ['currentTeamId']] }),
        loaders(({ props, cache, values }) => ({
            details: [
                null as ProductUsageDetails | null,
                {
                    loadDetails: async (_: void, breakpoint) => {
                        cache.disposables.dispose('productUsagePeople')
                        const columns = props.result.columns.map(({ key }) => key).sort()
                        if (!columns.length || !props.result.data.some(({ row }) => row === props.accountId)) {
                            return null
                        }
                        const matrix = props.result
                        const accountId = props.accountId
                        const previousPeople =
                            values.details?.matrix === matrix && values.details.accountId === accountId
                                ? values.details.people
                                : null
                        const controller = new AbortController()
                        const peopleQueryId = previousPeople ? null : uuid()
                        const firstsQueryId = props.includeFirstUse ? uuid() : null
                        const queryIds = [peopleQueryId, firstsQueryId].filter((id): id is string => id !== null)
                        const finished = new Set<string>()
                        const teamId = values.currentTeamId
                        cache.disposables.add(
                            () => () => {
                                controller.abort()
                                for (const queryId of queryIds) {
                                    if (!finished.has(queryId)) {
                                        void cancelQueryOnServer(teamId, queryId)
                                    }
                                }
                            },
                            'productUsagePeople',
                            { pauseOnPageHidden: false }
                        )
                        try {
                            const [people, firsts] = await Promise.all([
                                previousPeople
                                    ? Promise.resolve({ results: previousPeople })
                                    : performQuery<BookActivityPeopleQuery>(
                                          {
                                              kind: NodeKind.BookActivityPeopleQuery,
                                              accountIds: [props.accountId],
                                              dateRange: {
                                                  date_from: columns[0],
                                                  date_to: props.result.columns.find(
                                                      ({ key }) => key === columns[columns.length - 1]
                                                  )?.partial
                                                      ? null
                                                      : dayjs(columns[columns.length - 1])
                                                            .add(1, 'week')
                                                            .format('YYYY-MM-DD'),
                                              },
                                              interval: 'week',
                                              peopleLimit: 5,
                                              tags: CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS,
                                          },
                                          { signal: controller.signal },
                                          'blocking',
                                          peopleQueryId!
                                      ).finally(() => finished.add(peopleQueryId!)),
                                props.includeFirstUse
                                    ? performQuery<BookActivityFirstsQuery>(
                                          {
                                              kind: NodeKind.BookActivityFirstsQuery,
                                              accountIds: [props.accountId],
                                              tags: CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS,
                                          },
                                          { signal: controller.signal },
                                          'blocking',
                                          firstsQueryId!
                                      ).finally(() => finished.add(firstsQueryId!))
                                    : Promise.resolve(null),
                            ])
                            breakpoint()
                            return { matrix, accountId, people: people.results, firsts: firsts?.results ?? null }
                        } catch (error) {
                            breakpoint()
                            cache.disposables.dispose('productUsagePeople')
                            throw error
                        }
                    },
                },
            ],
        })),
        reducers({
            error: [
                null as string | null,
                {
                    loadDetails: () => null,
                    loadDetailsSuccess: () => null,
                    loadDetailsFailure: (_, { error }) => error,
                },
            ],
        }),
        afterMount(({ actions }) => actions.loadDetails()),
        propsChanged(({ actions, props }, previous) => {
            if (
                props.accountId !== previous.accountId ||
                props.result !== previous.result ||
                props.includeFirstUse !== previous.includeFirstUse
            ) {
                actions.loadDetails()
            }
        }),
    ])
