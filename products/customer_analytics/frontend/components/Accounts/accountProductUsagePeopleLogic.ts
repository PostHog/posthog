import { loaders } from 'kea-loaders'

import { dayjs } from 'lib/dayjs'
import { uuid } from 'lib/utils/dom'
import { teamLogic } from 'scenes/teamLogic'

import { cancelQueryOnServer } from '~/queries/nodes/DataNode/dataNodeLogic'
import { performQuery } from '~/queries/query'
import {
    NodeKind,
    type BookActivityMatrixResult,
    type BookActivityPeopleQuery,
    type BookActivityPeopleResult,
    type BookActivityFirstsQuery,
    type BookActivityFirstsResult,
} from '~/queries/schema/schema-general'

import { CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS } from '../../constants'

export interface AccountProductUsagePeopleLogicProps {
    instanceId: string
    accountId: string
    result: BookActivityMatrixResult
    includeFirstUse: boolean
}

interface ProductUsageDetails {
    matrix: BookActivityMatrixResult
    accountId: string
    people: BookActivityPeopleResult
    firsts: BookActivityFirstsResult | null
}

