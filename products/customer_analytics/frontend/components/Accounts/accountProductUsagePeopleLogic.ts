import { LogicWrapper, MakeLogicType, afterMount, connect, kea, key, path, props, propsChanged, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { dayjs } from 'lib/dayjs'
import { teamLogic } from 'scenes/teamLogic'

import {
    type BookActivityMatrixResult,
    type BookActivityPeopleResult,
    type BookActivityFirstsResult,
} from '~/queries/schema/schema-general'

import { ActivityQueryRequest } from '../ProductActivity/activityQueryRequest'
import { loadProductActivityDetails } from '../ProductActivity/loadProductActivityDetails'

export interface AccountProductUsagePeopleLogicProps {
    instanceId: string
    accountId: string
    result: BookActivityMatrixResult
    includeFirstUse: boolean
}

interface ProductUsageDetails {
    matrix: BookActivityMatrixResult
    accountId: string
    people: BookActivityPeopleResult
    firsts: BookActivityFirstsResult | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountProductUsagePeopleLogicValues {
    currentTeamId: number | null // teamLogic
    details: ProductUsageDetails | null
    detailsLoading: boolean
    error: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountProductUsagePeopleLogicActions {
    loadDetails: (_: void) => void
    loadDetailsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadDetailsSuccess: (
        details: ProductUsageDetails | null,
        payload?: void
    ) => {
        details: ProductUsageDetails | null
        payload?: void
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountProductUsagePeopleLogicMeta {
    key: string
}

export type accountProductUsagePeopleLogicType = MakeLogicType<
    accountProductUsagePeopleLogicValues,
    accountProductUsagePeopleLogicActions,
    AccountProductUsagePeopleLogicProps,
    accountProductUsagePeopleLogicMeta
>

export const accountProductUsagePeopleLogic: LogicWrapper<accountProductUsagePeopleLogicType> =
    kea<accountProductUsagePeopleLogicType>([
        props({} as AccountProductUsagePeopleLogicProps),
        key((props): string => props.instanceId),
        path((key) => ['products', 'customer_analytics', 'accountProductUsagePeopleLogic', key]),
        connect({ values: [teamLogic, ['currentTeamId']] }),
        loaders(({ props, cache, values }) => ({
            details: [
                null as ProductUsageDetails | null,
                {
                    loadDetails: async (_: void, breakpoint): Promise<ProductUsageDetails | null> => {
                        cache.disposables.dispose('productUsagePeople')
                        const columns = props.result.columns.map(({ key }) => key).sort()
                        if (!columns.length || !props.result.data.some(({ row }) => row === props.accountId)) {
                            return null
                        }
                        const matrix = props.result
                        const accountId = props.accountId
                        const previousPeople =
                            values.details?.matrix === matrix && values.details.accountId === accountId
                                ? values.details.people
                                : null
                        const request = new ActivityQueryRequest(
                            cache.disposables,
                            'productUsagePeople',
                            values.currentTeamId
                        )
                        try {
                            const { people, firsts } = await loadProductActivityDetails(request, {
                                accountIds: [accountId],
                                dateRange: {
                                    date_from: columns[0],
                                    date_to: matrix.columns.find(({ key }) => key === columns[columns.length - 1])
                                        ?.partial
                                        ? null
                                        : dayjs(columns[columns.length - 1])
                                              .add(1, 'week')
                                              .format('YYYY-MM-DD'),
                                },
                                interval: 'week',
                                peopleLimit: 5,
                                includePeople: true,
                                includeFirstUse: props.includeFirstUse,
                                previousPeople,
                            })
                            breakpoint()
                            return { matrix, accountId, people: people!, firsts }
                        } catch (error) {
                            breakpoint()
                            cache.disposables.dispose('productUsagePeople')
                            throw error
                        }
                    },
                },
            ],
        })),
        reducers({
            error: [
                null as string | null,
                {
                    loadDetails: () => null,
                    loadDetailsSuccess: () => null,
                    loadDetailsFailure: (_, { error }) => error,
                },
            ],
        }),
        afterMount(({ actions }) => actions.loadDetails()),
        propsChanged(({ actions, props }, previous) => {
            if (
                props.accountId !== previous.accountId ||
                props.result !== previous.result ||
                props.includeFirstUse !== previous.includeFirstUse
            ) {
                actions.loadDetails()
            }
        }),
    ])
