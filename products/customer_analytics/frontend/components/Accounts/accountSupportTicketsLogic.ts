import { MakeLogicType, afterMount, connect, kea, key, path, props } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'

import { accountsSupportTicketsList } from 'products/customer_analytics/frontend/generated/api'
import { SupportTicketApi } from 'products/customer_analytics/frontend/generated/api.schemas'

export interface AccountSupportTicketsLogicProps {
    accountId: string
}

// `tickets` is null when the load failed (view shows a "couldn't load" state) or hasn't run yet
// (distinguished from the NOT_LOADED sentinel below); an empty array is a linked account with no tickets.
export interface AccountSupportTicketsResult {
    tickets: SupportTicketApi[] | null
    loadFailed?: boolean
}

// Identity used as a "not loaded yet" sentinel by the view — every loaded outcome returns a fresh object.
export const NOT_LOADED: AccountSupportTicketsResult = { tickets: null }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountSupportTicketsLogicValues {
    currentTeamId: number | null // teamLogic
    ticketsResult: AccountSupportTicketsResult
    ticketsResultLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountSupportTicketsLogicActions {
    loadTickets: () => any
    loadTicketsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTicketsSuccess: (
        ticketsResult: AccountSupportTicketsResult,
        payload?: any
    ) => {
        ticketsResult: AccountSupportTicketsResult
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountSupportTicketsLogicMeta {
    key: string
}

export type accountSupportTicketsLogicType = MakeLogicType<
    accountSupportTicketsLogicValues,
    accountSupportTicketsLogicActions,
    AccountSupportTicketsLogicProps,
    accountSupportTicketsLogicMeta
>

export const accountSupportTicketsLogic = kea<accountSupportTicketsLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountSupportTicketsLogic', key]),
    props({} as AccountSupportTicketsLogicProps),
    key((props) => props.accountId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    loaders(({ props, values }) => ({
        ticketsResult: [
            NOT_LOADED,
            {
                loadTickets: async (): Promise<AccountSupportTicketsResult> => {
                    try {
                        const tickets = await accountsSupportTicketsList(String(values.currentTeamId), props.accountId)
                        return { tickets }
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountSupportTicketsLogic.loadTickets',
                        })
                        return { tickets: null, loadFailed: true }
                    }
                },
            },
        ],
    })),
    afterMount(({ actions }) => {
        actions.loadTickets()
    }),
])
