import { MakeLogicType, afterMount, connect, kea, key, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { insightsApi } from 'scenes/insights/utils/api'
import { teamLogic } from 'scenes/teamLogic'

import { DataVisualizationNode, HogQLVariable, NodeKind } from '~/queries/schema/schema-general'
import { InsightModel, InsightShortId } from '~/types'

import { accountsRetrieve } from 'products/customer_analytics/frontend/generated/api'

import { CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS } from '../../constants'

export interface AccountOpportunitiesLogicProps {
    accountId: string
    instanceId?: string
}

// The saved SQL insight behind the Opportunities tab, so a column change is an insight edit and not a code change.
// Other environments do not have it, so the tab shows a not-found state there.
export const OPPORTUNITIES_INSIGHT_SHORT_ID = 'xauPgpXt' as InsightShortId

// code_name of the SQL variable that limits the saved insight to one Salesforce account.
export const SALESFORCE_ACCOUNT_VARIABLE = 'salesforce_account_id'

// Outcomes: a null `sfdcId` means the account isn't linked to Salesforce; `insight` is null when the saved
// insight is absent from this environment. `loadFailed` is set when the account fetch errored, so the view
// shows a "couldn't load" state rather than hanging on the skeleton.
export interface AccountOpportunitiesResult {
    sfdcId: string | null
    insight: InsightModel | null
    loadFailed?: boolean
}

// Identity used as a "not loaded yet" sentinel by the view — every loaded outcome returns a fresh object.
export const NOT_LOADED: AccountOpportunitiesResult = { sfdcId: null, insight: null }

// An untagged ClickHouse query is rejected in local dev (UntaggedQueryError), and the saved SQL carries no tags.
function withQueryTags(insight: InsightModel): InsightModel {
    const query = insight.query
    if (!query || query.kind !== NodeKind.DataVisualizationNode) {
        return insight
    }
    const dataViz = query as DataVisualizationNode
    const taggedQuery: DataVisualizationNode = {
        ...dataViz,
        source: { ...dataViz.source, tags: { ...CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS, ...dataViz.source.tags } },
    }
    return { ...insight, query: taggedQuery as InsightModel['query'] }
}

// Returns null when the saved SQL does not filter by the account variable, because the table would then list
// the opportunities of every account.
function buildVariablesOverride(
    insight: InsightModel | null,
    sfdcId: string | null
): Record<string, HogQLVariable> | null {
    const query = insight?.query
    if (!sfdcId || !query || query.kind !== NodeKind.DataVisualizationNode) {
        return null
    }
    const source = (query as DataVisualizationNode).source
    const variable = Object.values(source.variables ?? {}).find(
        ({ code_name }) => code_name === SALESFORCE_ACCOUNT_VARIABLE
    )
    if (!variable || !source.query.includes(`variables.${SALESFORCE_ACCOUNT_VARIABLE}`)) {
        return null
    }
    return { [variable.variableId]: { ...variable, value: sfdcId } }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountOpportunitiesLogicValues {
    currentTeamId: number | null // teamLogic
    opportunitiesResult: AccountOpportunitiesResult
    opportunitiesResultLoading: boolean
    variablesOverride: Record<string, HogQLVariable> | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountOpportunitiesLogicActions {
    loadOpportunities: () => any
    loadOpportunitiesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadOpportunitiesSuccess: (
        opportunitiesResult: AccountOpportunitiesResult,
        payload?: any
    ) => {
        opportunitiesResult: AccountOpportunitiesResult
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountOpportunitiesLogicMeta {
    key: string
}

export type accountOpportunitiesLogicType = MakeLogicType<
    accountOpportunitiesLogicValues,
    accountOpportunitiesLogicActions,
    AccountOpportunitiesLogicProps,
    accountOpportunitiesLogicMeta
>

export const accountOpportunitiesLogic = kea<accountOpportunitiesLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountOpportunitiesLogic', key]),
    props({} as AccountOpportunitiesLogicProps),
    key((props) => `${props.accountId}:${props.instanceId ?? 'default'}`),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    loaders(({ props, values }) => ({
        opportunitiesResult: [
            NOT_LOADED,
            {
                loadOpportunities: async (): Promise<AccountOpportunitiesResult> => {
                    let sfdcId: string | null
                    try {
                        const account = await accountsRetrieve(String(values.currentTeamId), props.accountId)
                        sfdcId = account.properties?.sfdc_id ?? null
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountOpportunitiesLogic.loadOpportunities',
                        })
                        return { sfdcId: null, insight: null, loadFailed: true }
                    }
                    if (!sfdcId) {
                        return { sfdcId: null, insight: null }
                    }
                    try {
                        const insight = await insightsApi.getByShortId(OPPORTUNITIES_INSIGHT_SHORT_ID)
                        return { sfdcId, insight: insight ? withQueryTags(insight) : null }
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountOpportunitiesLogic.loadOpportunities',
                            shortId: OPPORTUNITIES_INSIGHT_SHORT_ID,
                        })
                        return { sfdcId, insight: null }
                    }
                },
            },
        ],
    })),
    selectors({
        variablesOverride: [
            (s) => [s.opportunitiesResult],
            ({ insight, sfdcId }: AccountOpportunitiesResult): Record<string, HogQLVariable> | null =>
                buildVariablesOverride(insight, sfdcId),
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadOpportunities()
    }),
])
