export const accountSessionReplaysLogic: LogicWrapper<accountSessionReplaysLogicType> =
    kea<accountSessionReplaysLogicType>([
        props({} as AccountSessionReplaysLogicProps),
        key((props) => `${props.projectId}:${props.accountId}:${props.externalId}:${props.instanceId ?? 'default'}`),
        path((key) => ['products', 'customerAnalytics', 'accountSessionReplaysLogic', key]),
        connect({ values: [teamLogic, ['customerAnalyticsConfig']] }),
        actions({
            setDateRange: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
            setUser: (user: AccountReplayUserOption | null) => ({ user }),
            loadMore: true,
            retry: true,
            openRecording: (id: string) => ({ id }),
        }),
        loaders(({ props, values }) => ({
            replayList: [
                null as AccountReplayListState | null,
                {
                    loadReplayList: async (
                        { append }: { append: boolean },
                        breakpoint
                    ): Promise<AccountReplayListState> => {
                        const previous = append ? values.replayList : null
                        if (!values.canViewReplays) {
                            return { ...EMPTY_LIST, status: 'denied' }
                        }
                        if (props.projectId == null) {
                            return EMPTY_LIST
                        }
                        const query = createAccountReplayQuery(
                            props.externalId,
                            values.customerAnalyticsConfig.account_group_type_index,
                            values.dateRange,
                            values.selectedUser?.value ?? null,
                            previous ? { cursor: previous.nextCursor, offset: previous.nextOffset } : undefined
                        )
                        if (!query) {
                            return { ...EMPTY_LIST, status: 'setup' }
                        }
                        try {
                            const response = await getAccountReplayRecordings(props.projectId, query)
                            breakpoint()
                            const recordings = [
                                ...new Map(
                                    [...(previous?.recordings ?? []), ...response.results].map((recording) => [
                                        recording.id,
                                        recording,
                                    ])
                                ).values(),
                            ]
                            return {
                                status: 'ready',
                                recordings,
                                hasMore:
                                    response.has_next &&
                                    response.results.length > 0 &&
                                    (!response.next_cursor || response.next_cursor !== previous?.nextCursor),
                                nextCursor: response.next_cursor,
                                nextOffset: (previous?.nextOffset ?? 0) + response.results.length,
                            }
                        } catch (error) {
                            if (error instanceof Error && isBreakpoint(error)) {
                                throw error
                            }
                            breakpoint()
                            const denied = error instanceof ApiError && (error.status === 401 || error.status === 403)
                            posthog.capture(AccountsEvents.ReplaysLoadFailed, {
                                failure_type: denied ? 'denied' : 'request',
                            })
                            return denied
                                ? { ...EMPTY_LIST, status: 'denied' }
                                : {
                                      ...(previous ?? EMPTY_LIST),
                                      status: 'error',
                                      failedPage: append ? 'more' : 'first',
                                  }
                        }
                    },
                },
            ],
        })),
        reducers(({ props }) => ({
            dateRange: [
                getAccountReplayDateRange(props.initialConfig),
                { setDateRange: (_, { dateFrom, dateTo }) => ({ date_from: dateFrom, date_to: dateTo }) },
            ],
            selectedUser: [null as AccountReplayUserOption | null, { setUser: (_, { user }) => user }],
            replayList: { setDateRange: () => null, setUser: () => null },
            availableUsers: [
                [] as AccountReplayUserOption[],
                {
                    setDateRange: () => [],
                    loadReplayListSuccess: (users, { replayList }) => {
                        if (replayList?.status !== 'ready') {
                            return replayList?.status === 'denied' || replayList?.status === 'setup' ? [] : users
                        }
                        const options = replayList.recordings.flatMap(({ person }) =>
                            person?.uuid ? [{ value: person.uuid, label: person.name || person.uuid }] : []
                        )
                        return [...new Map([...users, ...options].map((user) => [user.value, user])).values()]
                    },
                },
            ],
        })),
        selectors({
            canViewReplays: [
                () => [],
                (): boolean =>
                    userHasAccess(AccessControlResourceType.CustomerAnalytics, AccessControlLevel.Viewer) &&
                    userHasAccess(AccessControlResourceType.SessionRecording, AccessControlLevel.Viewer),
            ],
        }),
        listeners(({ actions, values, props }) => ({
            setDateRange: () => {
                props.onConfigChange?.({ dateRange: values.dateRange })
                posthog.capture(AccountsEvents.ReplaysFilterChanged, { filter_type: 'date' })
                actions.loadReplayList({ append: false })
            },
            setUser: () => {
                posthog.capture(AccountsEvents.ReplaysFilterChanged, {
                    filter_type: 'user',
                    is_cleared: !values.selectedUser,
                })
                actions.loadReplayList({ append: false })
            },
            loadMore: () => {
                if (values.replayListLoading || !values.replayList?.hasMore || values.replayList.status !== 'ready') {
                    return
                }
                posthog.capture(AccountsEvents.ReplaysLoadMore, { page_size: ACCOUNT_REPLAYS_PAGE_SIZE })
                actions.loadReplayList({ append: true })
            },
            retry: () => {
                if (!values.replayListLoading) {
                    posthog.capture(AccountsEvents.ReplaysRetried)
                    actions.loadReplayList({ append: values.replayList?.failedPage === 'more' })
                }
            },
            openRecording: ({ id }) => {
                if (
                    values.canViewReplays &&
                    values.replayList?.status !== 'denied' &&
                    values.replayList?.recordings.some((recording) => recording.id === id)
                ) {
                    posthog.capture(AccountsEvents.ReplaysRecordingOpened)
                    sessionPlayerModalLogic.actions.openSessionPlayer({ id })
                }
            },
            [teamLogic.actionTypes.loadCurrentTeamSuccess]: () => actions.loadReplayList({ append: false }),
            [teamLogic.actionTypes.updateCurrentTeamSuccess]: () => actions.loadReplayList({ append: false }),
        })),
        afterMount(({ actions }) => {
            posthog.capture(AccountsEvents.ReplaysViewed)
            actions.loadReplayList({ append: false })
        }),
    ])
