export interface accountEmailThreadsLogicMeta {
    key: string
}

export type accountEmailThreadsLogicType = MakeLogicType<
    accountEmailThreadsLogicValues,
    accountEmailThreadsLogicActions,
    AccountEmailThreadsLogicProps,
    accountEmailThreadsLogicMeta
>

export const accountEmailThreadsLogic = kea<accountEmailThreadsLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountEmailThreadsLogic', key]),
    props({} as AccountEmailThreadsLogicProps),
    key((props) => props.accountId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        setPage: (page: number) => ({ page }),
        openThread: (threadId: string) => ({ threadId }),
        closeThread: (threadId: string) => ({ threadId }),
        loadThreadDetail: (threadId: string) => ({ threadId }),
        loadThreadDetailSuccess: (threadId: string, detail: AccountEmailThreadDetailApi) => ({ threadId, detail }),
        loadThreadDetailFailure: (threadId: string) => ({ threadId }),
    }),
    loaders(({ props, values }) => ({
        threadsResult: [
            NOT_LOADED,
            {
                loadThreads: async (): Promise<AccountEmailThreadsResult> => {
                    try {
                        const response = await accountsEmailThreadsList(String(values.currentTeamId), props.accountId, {
                            limit: PAGE_SIZE,
                            offset: (values.page - 1) * PAGE_SIZE,
                        })
                        return { threads: [...response.results], count: response.count }
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountEmailThreadsLogic.loadThreads',
                        })
                        return { threads: null, count: 0, loadFailed: true }
                    }
                },
            },
        ],
    })),
    reducers({
        page: [
            1,
            {
                setPage: (_, { page }) => page,
            },
        ],
        expandedThreadId: [
            null as string | null,
            {
                openThread: (_, { threadId }) => threadId,
                closeThread: (state, { threadId }) => (state === threadId ? null : state),
                setPage: () => null,
            },
        ],
        threadDetails: [
            {} as Record<string, AccountEmailThreadDetailApi>,
            {
                loadThreadDetailSuccess: (state, { threadId, detail }) => ({ ...state, [threadId]: detail }),
            },
        ],
        threadDetailsLoading: [
            {} as Record<string, boolean>,
            {
                loadThreadDetail: (state, { threadId }) => ({ ...state, [threadId]: true }),
                loadThreadDetailSuccess: (state, { threadId }) => ({ ...state, [threadId]: false }),
                loadThreadDetailFailure: (state, { threadId }) => ({ ...state, [threadId]: false }),
            },
        ],
        threadDetailErrors: [
            {} as Record<string, boolean>,
            {
                loadThreadDetail: (state, { threadId }) => ({ ...state, [threadId]: false }),
                loadThreadDetailSuccess: (state, { threadId }) => ({ ...state, [threadId]: false }),
                loadThreadDetailFailure: (state, { threadId }) => ({ ...state, [threadId]: true }),
            },
        ],
    }),
    listeners(({ actions, values, props }) => ({
        setPage: () => actions.loadThreads(),
        openThread: ({ threadId }) => {
            if (!values.threadDetails[threadId] && !values.threadDetailsLoading[threadId]) {
                actions.loadThreadDetail(threadId)
            }
        },
        loadThreadDetail: async ({ threadId }) => {
            try {
                const detail = await accountsEmailThreadsRetrieve(
                    String(values.currentTeamId),
                    props.accountId,
                    threadId
                )
                actions.loadThreadDetailSuccess(threadId, detail)
            } catch (error) {
                posthog.captureException(error as Error, {
                    scope: 'accountEmailThreadsLogic.loadThreadDetail',
                })
                actions.loadThreadDetailFailure(threadId)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadThreads()
    }),
])
