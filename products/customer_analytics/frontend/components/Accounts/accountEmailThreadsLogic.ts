import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'

import {
    accountsEmailThreadMessagesList,
    accountsEmailThreadsList,
} from 'products/customer_analytics/frontend/generated/api'
import type {
    AccountEmailThreadApi,
    PaginatedAccountEmailThreadMessageListApi,
} from 'products/customer_analytics/frontend/generated/api.schemas'

export const PAGE_SIZE = 10
export const MESSAGE_PAGE_SIZE = 50

export interface AccountEmailThreadsLogicProps {
    accountId: string
}

export interface AccountEmailThreadsResult {
    threads: AccountEmailThreadApi[] | null
    count: number
    loadFailed?: boolean
}

export const NOT_LOADED: AccountEmailThreadsResult = { threads: null, count: 0 }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountEmailThreadsLogicValues {
    currentTeamId: number | null // teamLogic
    expandedThreadId: string | null
    page: number
    threadDetailErrors: Record<string, boolean>
    threadDetailPages: Record<string, number>
    threadDetails: Record<string, PaginatedAccountEmailThreadMessageListApi>
    threadDetailsLoading: Record<string, boolean>
    threadsResult: AccountEmailThreadsResult
    threadsResultLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountEmailThreadsLogicActions {
    closeThread: (threadId: string) => {
        threadId: string
    }
    loadThreadDetail: (threadId: string) => {
        threadId: string
    }
    loadThreadDetailFailure: (threadId: string) => {
        threadId: string
    }
    loadThreadDetailSuccess: (
        threadId: string,
        detail: PaginatedAccountEmailThreadMessageListApi
    ) => {
        detail: PaginatedAccountEmailThreadMessageListApi
        threadId: string
    }
    loadThreads: (_?: any) => any
    loadThreadsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadThreadsSuccess: (
        threadsResult: AccountEmailThreadsResult,
        payload?: any
    ) => {
        threadsResult: AccountEmailThreadsResult
        payload?: any
    }
    openThread: (threadId: string) => {
        threadId: string
    }
    setPage: (page: number) => {
        page: number
    }
    setThreadDetailPage: (
        threadId: string,
        page: number
    ) => {
        page: number
        threadId: string
    }
}

