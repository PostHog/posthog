export type accountDotMatrixTileLogicType = MakeLogicType<
    accountDotMatrixTileLogicValues,
    accountDotMatrixTileLogicActions,
    AccountDotMatrixTileLogicProps,
    accountDotMatrixTileLogicMeta
>

export const accountDotMatrixTileLogic: LogicWrapper<accountDotMatrixTileLogicType> =
    kea<accountDotMatrixTileLogicType>([
        props({} as AccountDotMatrixTileLogicProps),
        key(({ instanceId }) => instanceId),
        path((key) => ['products', 'customer_analytics', 'accountDotMatrixTileLogic', key]),
        connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
        actions({
            restoreConfig: (config: DotMatrixTileConfig) => ({ config }),
            setMode: (mode: 'dots' | 'count') => ({ mode }),
            setWeeks: (weeks: DotMatrixWeeks) => ({ weeks }),
            setSelectedSeries: (selectedSeries: string[]) => ({ selectedSeries }),
            retry: true,
        }),
        loaders(({ cache, props, values }) => ({
            accountActivityMatrix: [
                null as AccountActivityMatrixResult | null,
                {
                    loadAccountActivityMatrix: async (_ = undefined, breakpoint) => {
                        const query: AccountActivityMatrixQuery = {
                            kind: NodeKind.AccountActivityMatrixQuery,
                            accountId: props.accountId,
                            weeks: values.config.weeks,
                        }
                        const controller = new AbortController()
                        const queryId = uuid()
                        const teamId = values.currentTeamId
                        let finished = false
                        cache.disposables.add(
                            () => () => {
                                controller.abort()
                                if (!finished) {
                                    void cancelQueryOnServer(teamId, queryId)
                                }
                            },
                            'accountActivityMatrixRequest',
                            { pauseOnPageHidden: false }
                        )
                        try {
                            const response = await performQuery(
                                query,
                                { signal: controller.signal },
                                'blocking',
                                queryId
                            )
                            finished = true
                            breakpoint()
                            return response.results
                        } catch (error) {
                            finished = true
                            breakpoint()
                            throw error
                        }
                    },
                },
            ],
        })),
        reducers(({ props }) => ({
            config: [
                getDotMatrixTileConfig(props.initialConfig),
                {
                    restoreConfig: (_, { config }) => config,
                    setMode: (config, { mode }) => ({ ...config, mode }),
                    setWeeks: (config, { weeks }) => ({ ...config, weeks }),
                    setSelectedSeries: (config, { selectedSeries }) => ({ ...config, selectedSeries }),
                },
            ],
            loadFailed: [
                false,
                {
                    loadAccountActivityMatrix: () => false,
                    loadAccountActivityMatrixSuccess: () => false,
                    loadAccountActivityMatrixFailure: () => true,
                },
            ],
        })),
        selectors({
            selectedSeries: [
                (s) => [s.config, s.accountActivityMatrix],
                (config: DotMatrixTileConfig, matrix: AccountActivityMatrixResult | null): string[] =>
                    keepKnownSeries(config.selectedSeries, matrix),
            ],
            matrixProps: [
                (s) => [s.accountActivityMatrix, s.selectedSeries],
                (matrix: AccountActivityMatrixResult | null, selectedSeries: string[]): AccountActivityMatrixProps =>
                    getAccountActivityMatrixProps(matrix ?? EMPTY_ACCOUNT_ACTIVITY_MATRIX, selectedSeries),
            ],
        }),
        listeners(({ actions, props, values }) => ({
            setMode: ({ mode }) => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSettingChanged, {
                    setting: 'mode' satisfies DotMatrixSetting,
                    value: mode,
                })
            },
            setWeeks: ({ weeks }) => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSettingChanged, {
                    setting: 'weeks' satisfies DotMatrixSetting,
                    value: weeks,
                })
                actions.loadAccountActivityMatrix()
            },
            setSelectedSeries: ({ selectedSeries }) => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSeriesSelected, { selected_count: selectedSeries.length })
            },
            retry: () => {
                posthog.capture(AccountsEvents.DotMatrixRetried)
                actions.loadAccountActivityMatrix()
            },
            loadAccountActivityMatrixFailure: ({ errorObject }) => {
                const denied = errorObject?.status === 403
                posthog.capture(AccountsEvents.DotMatrixLoadFailed, {
                    failure_type: (denied ? 'denied' : 'request') satisfies DotMatrixLoadFailure,
                })
                if (!denied) {
                    posthog.captureException(errorObject, { scope: 'accountDotMatrixTileLogic' })
                }
            },
        })),
        propsChanged(({ actions, props, values }, previousProps) => {
            const nextConfig = getDotMatrixTileConfig(props.initialConfig)
            const accountChanged = props.accountId !== previousProps.accountId
            let weeksChanged = false
            if (!objectsEqual(nextConfig, getDotMatrixTileConfig(previousProps.initialConfig))) {
                weeksChanged = nextConfig.weeks !== values.config.weeks
                actions.restoreConfig(nextConfig)
            }
            if (accountChanged || weeksChanged) {
                actions.loadAccountActivityMatrix()
            }
        }),
        afterMount(({ actions }) => {
            posthog.capture(AccountsEvents.DotMatrixViewed)
            actions.loadAccountActivityMatrix()
        }),
    ])
