export const accountDotMatrixTileLogic: LogicWrapper<accountDotMatrixTileLogicType> =
    kea<accountDotMatrixTileLogicType>([
        props({} as AccountDotMatrixTileLogicProps),
        key(({ instanceId }) => instanceId),
        path((key) => ['products', 'customer_analytics', 'accountDotMatrixTileLogic', key]),
        connect(() => ({ values: [teamLogic, ['currentTeamId', 'customerAnalyticsConfig']] })),
        actions({
            restoreConfig: (config: DotMatrixTileConfig) => ({ config }),
            chooseSource: (kind: DotMatrixTileSource['kind'] | null) => ({ kind }),
            setMode: (mode: 'dots' | 'count') => ({ mode }),
            setWeeks: (weeks: DotMatrixWeeks) => ({ weeks }),
            setSelectedSeries: (selectedSeries: string[]) => ({ selectedSeries }),
            editQuery: true,
            setQueryDraft: (query: string) => ({ query }),
            setMappingDraft: (mapping: DotMatrixSourceMapping) => ({ mapping }),
            runQuery: true,
            saveQuery: true,
            applyQuery: (source: DotMatrixTileSource) => ({ source }),
            retry: true,
        }),
        loaders(({ cache, props, values }) => ({
            matrixResult: [
                null as DotMatrixTileResult | null,
                {
                    loadMatrix: async (
                        source: DotMatrixTileSource | null = values.config.source === undefined
                            ? { kind: 'usage_metrics' }
                            : values.config.source,
                        breakpoint
                    ) => {
                        cache.disposables.dispose('dotMatrixRequest')
                        if (!source) {
                            return null
                        }
                        const controller = new AbortController()
                        const queryId = uuid()
                        const teamId = values.currentTeamId
                        let finished = false
                        cache.disposables.add(
                            () => () => {
                                controller.abort()
                                if (!finished) {
                                    void cancelQueryOnServer(teamId, queryId)
                                }
                            },
                            'dotMatrixRequest',
                            { pauseOnPageHidden: false }
                        )
                        try {
                            const result = await queryDotMatrixSource(
                                source,
                                {
                                    accountId: props.accountId,
                                    externalId: props.externalId,
                                    groupTypeIndex: values.customerAnalyticsConfig.account_group_type_index,
                                    weeks: values.config.weeks,
                                },
                                controller.signal,
                                queryId
                            )
                            finished = true
                            breakpoint()
                            return result
                        } catch (error) {
                            finished = true
                            breakpoint()
                            throw error
                        }
                    },
                },
            ],
        })),
        reducers(({ props }) => ({
            config: [
                getDotMatrixTileConfig(props.initialConfig),
                {
                    restoreConfig: (_, { config }) => config,
                    chooseSource: (config, { kind }) => ({
                        ...config,
                        selectedSeries: [],
                        source: kind && kind !== 'hogql' ? { kind } : null,
                    }),
                    applyQuery: (config, { source }) => ({ ...config, selectedSeries: [], source }),
                    setMode: (config, { mode }) => ({ ...config, mode }),
                    setWeeks: (config, { weeks }) => ({ ...config, weeks }),
                    setSelectedSeries: (config, { selectedSeries }) => ({ ...config, selectedSeries }),
                },
            ],
            queryEditorOpen: [
                false,
                {
                    chooseSource: (_, { kind }) => kind === 'hogql',
                    editQuery: () => true,
                    applyQuery: () => false,
                    restoreConfig: () => false,
                },
            ],
            queryDraft: [
                DEFAULT_MATRIX_QUERY,
                {
                    setQueryDraft: (_, { query }) => query,
                },
            ],
            mappingDraft: [
                DEFAULT_MATRIX_MAPPING as DotMatrixSourceMapping,
                {
                    setMappingDraft: (_, { mapping }) => mapping,
                },
            ],
            loadError: [
                null as string | null,
                {
                    loadMatrix: () => null,
                    loadMatrixSuccess: () => null,
                    loadMatrixFailure: (_, { error }) => error,
                },
            ],
        })),
        selectors({
            sourceKind: [
                (s) => [s.config, s.queryEditorOpen],
                (config: DotMatrixTileConfig, editing: boolean): DotMatrixTileSource['kind'] | null =>
                    editing ? 'hogql' : config.source === undefined ? 'usage_metrics' : (config.source?.kind ?? null),
            ],
            activeMapping: [
                (s) => [s.config, s.queryEditorOpen, s.mappingDraft],
                (
                    config: DotMatrixTileConfig,
                    editing: boolean,
                    draft: DotMatrixSourceMapping
                ): DotMatrixSourceMapping =>
                    editing ? draft : config.source?.kind === 'hogql' ? config.source.mapping : DEFAULT_MATRIX_MAPPING,
            ],
            presentation: [
                (s) => [s.matrixResult, s.config, s.activeMapping],
                (result: DotMatrixTileResult | null, config: DotMatrixTileConfig, mapping: DotMatrixSourceMapping) =>
                    getDotMatrixTilePresentation(result, config.selectedSeries, mapping, config.weeks),
            ],
            selectedSeries: [
                (s) => [s.config, s.presentation],
                (
                    config: DotMatrixTileConfig,
                    presentation: ReturnType<typeof getDotMatrixTilePresentation>
                ): string[] => {
                    const known = new Set(
                        presentation.matrix.series?.map(({ key }) => key) ??
                            presentation.matrix.data.map(({ series }) => series)
                    )
                    return known.size ? config.selectedSeries.filter((key) => known.has(key)) : config.selectedSeries
                },
            ],
            querySaveError: [
                (s) => [s.matrixResult, s.queryDraft, s.mappingDraft, s.matrixResultLoading, s.loadError],
                (
                    result: DotMatrixTileResult | null,
                    query: string,
                    mapping: DotMatrixSourceMapping,
                    loading: boolean,
                    error: string | null
                ): string | null => {
                    if (loading) {
                        return 'Wait for the query to finish.'
                    }
                    if (error || result?.kind !== 'hogql' || result.query !== query) {
                        return 'Run the query before saving.'
                    }
                    return getHogQLActivityMatrix(result.result, mapping).error
                },
            ],
        }),
        listeners(({ actions, props, values }) => ({
            chooseSource: ({ kind }) => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSourceSelected, { source_kind: kind })
                if (kind === 'hogql') {
                    actions.setQueryDraft(DEFAULT_MATRIX_QUERY)
                    actions.setMappingDraft(DEFAULT_MATRIX_MAPPING)
                }
                actions.loadMatrix()
            },
            editQuery: () => {
                if (values.config.source?.kind === 'hogql') {
                    actions.setQueryDraft(values.config.source.query)
                    actions.setMappingDraft(values.config.source.mapping)
                }
            },
            runQuery: () => {
                if (!values.queryDraft.trim() || values.matrixResultLoading) {
                    return
                }
                posthog.capture(AccountsEvents.DotMatrixQueryRun, { source_kind: 'hogql' })
                actions.loadMatrix({ kind: 'hogql', query: values.queryDraft, mapping: values.mappingDraft })
            },
            saveQuery: () => {
                if (!values.querySaveError) {
                    actions.applyQuery({ kind: 'hogql', query: values.queryDraft, mapping: values.mappingDraft })
                }
            },
            applyQuery: () => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSourceConfigured, { source_kind: 'hogql' })
            },
            setMode: ({ mode }) => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSettingChanged, { setting: 'mode', value: mode })
            },
            setWeeks: ({ weeks }) => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSettingChanged, { setting: 'weeks', value: weeks })
                actions.loadMatrix(values.queryEditorOpen ? null : undefined)
            },
            setSelectedSeries: ({ selectedSeries }) => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSeriesSelected, { selected_count: selectedSeries.length })
            },
            retry: () => {
                posthog.capture(AccountsEvents.DotMatrixRetried)
                if (values.queryEditorOpen) {
                    actions.runQuery()
                } else {
                    actions.loadMatrix()
                }
            },
            loadMatrixFailure: ({ errorObject }) => {
                posthog.capture(AccountsEvents.DotMatrixLoadFailed, {
                    failure_type: errorObject?.status === 403 ? 'denied' : 'request',
                    source_kind: values.sourceKind,
                })
            },
        })),
        propsChanged(({ actions, props, values }, previousProps) => {
            const next = getDotMatrixTileConfig(props.initialConfig)
            let queryChanged = false
            if (
                !objectsEqual(next, getDotMatrixTileConfig(previousProps.initialConfig)) &&
                !objectsEqual(next, values.config)
            ) {
                queryChanged = next.weeks !== values.config.weeks || !objectsEqual(next.source, values.config.source)
                actions.restoreConfig(next)
            }
            if (
                props.accountId !== previousProps.accountId ||
                props.externalId !== previousProps.externalId ||
                queryChanged
            ) {
                actions.loadMatrix(values.queryEditorOpen ? null : undefined)
            }
        }),
        afterMount(({ actions }) => {
            posthog.capture(AccountsEvents.DotMatrixViewed)
            actions.loadMatrix()
        }),
    ])
