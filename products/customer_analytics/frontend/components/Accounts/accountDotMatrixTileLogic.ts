import {
    LogicWrapper,
    MakeLogicType,
    actions,
    kea,
    key,
    listeners,
    path,
    props,
    propsChanged,
    reducers,
    selectors,
} from 'kea'

import { getDotMatrixDemoPresentation } from 'lib/components/DotMatrix/dotMatrixDemoData'
import {
    getDotMatrixMockDataset,
    type DotMatrixMockDataset,
    type DotMatrixMockDatasetName,
} from 'lib/components/DotMatrix/mocks'
import { objectsEqual } from 'lib/utils/objects'

import type { AccountViewTileLogicProps } from './accountViewTileConfig'
import { getDotMatrixTileConfig, type DotMatrixTileConfig } from './dotMatrixTileConfig'

export interface AccountDotMatrixTileLogicProps extends AccountViewTileLogicProps {
    instanceId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountDotMatrixTileLogicValues {
    config: DotMatrixTileConfig
    datasetName: DotMatrixMockDatasetName
    dataset: DotMatrixMockDataset
    presentation: ReturnType<typeof getDotMatrixDemoPresentation>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountDotMatrixTileLogicActions {
    restoreConfig: (config: DotMatrixTileConfig) => {
        config: DotMatrixTileConfig
    }
    setDataset: (dataset: DotMatrixMockDatasetName) => {
        dataset: DotMatrixMockDatasetName
    }
    setMode: (mode: 'count' | 'dots') => {
        mode: 'count' | 'dots'
    }
    setSelectedSeries: (selectedSeries: string[]) => {
        selectedSeries: string[]
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountDotMatrixTileLogicMeta {
    key: string
}

export type accountDotMatrixTileLogicType = MakeLogicType<
    accountDotMatrixTileLogicValues,
    accountDotMatrixTileLogicActions,
    AccountDotMatrixTileLogicProps,
    accountDotMatrixTileLogicMeta
>

export const accountDotMatrixTileLogic: LogicWrapper<accountDotMatrixTileLogicType> =
    kea<accountDotMatrixTileLogicType>([
        props({} as AccountDotMatrixTileLogicProps),
        key(({ instanceId }) => instanceId),
        path((key) => ['products', 'customer_analytics', 'accountDotMatrixTileLogic', key]),
        actions({
            restoreConfig: (config: DotMatrixTileConfig) => ({ config }),
            setDataset: (dataset: DotMatrixMockDatasetName) => ({ dataset }),
            setMode: (mode: 'dots' | 'count') => ({ mode }),
            setSelectedSeries: (selectedSeries: string[]) => ({ selectedSeries }),
        }),
        reducers(({ props }) => ({
            config: [
                getDotMatrixTileConfig(props.initialConfig),
                {
                    restoreConfig: (_, { config }) => config,
                    setDataset: (config, { dataset }) => ({ ...config, dataset, selectedSeries: [] }),
                    setMode: (config, { mode }) => ({ ...config, mode }),
                    setSelectedSeries: (config, { selectedSeries }) => ({ ...config, selectedSeries }),
                },
            ],
        })),
        selectors({
            datasetName: [(s) => [s.config], (config): DotMatrixMockDatasetName => config.dataset],
            dataset: [
                (s) => [s.datasetName],
                (datasetName): DotMatrixMockDataset => getDotMatrixMockDataset(datasetName),
            ],
            presentation: [
                (s) => [s.config],
                (config): ReturnType<typeof getDotMatrixDemoPresentation> =>
                    getDotMatrixDemoPresentation(config.dataset, config.selectedSeries),
            ],
        }),
        listeners(({ props, values }) => ({
            setDataset: () => props.onConfigChange?.({ ...values.config }),
            setMode: () => props.onConfigChange?.({ ...values.config }),
            setSelectedSeries: () => props.onConfigChange?.({ ...values.config }),
        })),
        propsChanged(({ actions, props }, previousProps) => {
            const nextConfig = getDotMatrixTileConfig(props.initialConfig)
            if (!objectsEqual(nextConfig, getDotMatrixTileConfig(previousProps.initialConfig))) {
                actions.restoreConfig(nextConfig)
            }
        }),
    ])
