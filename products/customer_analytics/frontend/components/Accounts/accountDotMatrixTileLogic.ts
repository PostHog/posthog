function confirmDiscard(dirty: boolean, discard: () => void): void {
    if (!dirty) {
        discard()
        return
    }
    LemonDialog.open({
        title: 'Discard your query changes?',
        description: 'Your edits to this query have not been saved.',
        primaryButton: { children: 'Discard changes', status: 'danger', onClick: () => discard() },
        secondaryButton: { children: 'Keep editing' },
    })
}

export const accountDotMatrixTileLogic: LogicWrapper<accountDotMatrixTileLogicType> =
    kea<accountDotMatrixTileLogicType>([
        props({} as AccountDotMatrixTileLogicProps),
        key(({ instanceId }) => instanceId),
        path((key) => ['products', 'customer_analytics', 'accountDotMatrixTileLogic', key]),
        connect(() => ({ values: [teamLogic, ['currentTeamId', 'customerAnalyticsConfig', 'weekStartDay']] })),
        actions({
            restoreConfig: (config: DotMatrixTileConfig) => ({ config }),
            chooseSource: (kind: DotMatrixTileSource['kind'] | null) => ({ kind }),
            applySource: (kind: DotMatrixPresetSourceKind) => ({ kind }),
            cancelQuery: true,
            setMode: (mode: 'dots' | 'count') => ({ mode }),
            setWeeks: (weeks: DotMatrixWeeks) => ({ weeks }),
            setIncludeFirstUse: (includeFirstUse: boolean) => ({ includeFirstUse }),
            setSelectedSeries: (selectedSeries: string[]) => ({ selectedSeries }),
            editQuery: true,
            setQueryDraft: (query: string) => ({ query }),
            setMappingDraft: (mapping: DotMatrixSourceMapping) => ({ mapping }),
            runQuery: true,
            saveQuery: true,
            applyQuery: (source: DotMatrixTileSource) => ({ source }),
            restoreFailedSave: true,
            refreshMatrix: true,
            retry: true,
        }),
        loaders(({ cache, props, values }) => ({
            matrixResult: [
                null as DotMatrixTileResult | null,
                {
                    loadMatrix: async (
                        source: DotMatrixTileSource | null = values.config.source === undefined
                            ? { kind: 'usage_metrics' }
                            : values.config.source,
                        breakpoint
                    ) => {
                        cache.disposables.dispose('dotMatrixRequest')
                        if (!source) {
                            return null
                        }
                        const request = new ActivityQueryRequest(
                            cache.disposables,
                            'dotMatrixRequest',
                            values.currentTeamId
                        )
                        try {
                            const result = await request.run((signal, queryId) =>
                                queryDotMatrixSource(
                                    source,
                                    {
                                        accountId: props.accountId,
                                        externalId: props.externalId,
                                        groupTypeIndex: values.customerAnalyticsConfig.account_group_type_index,
                                        weeks: values.config.weeks,
                                        weekStartDay: values.weekStartDay,
                                        includeFirstUse: false,
                                    },
                                    signal,
                                    queryId
                                )
                            )
                            breakpoint()
                            return result
                        } catch (error) {
                            breakpoint()
                            throw error
                        }
                    },
                },
            ],
        })),
        reducers(({ props }) => ({
            config: [
                getDotMatrixTileConfig(props.initialConfig),
                {
                    restoreConfig: (_, { config }) => config,
                    applySource: (config, { kind }) => ({ ...config, selectedSeries: [], source: { kind } }),
                    applyQuery: (config, { source }) => ({ ...config, selectedSeries: [], source }),
                    setMode: (config, { mode }) => ({ ...config, mode }),
                    setWeeks: (config, { weeks }) => ({ ...config, weeks }),
                },
            ],
            includeFirstUse: [
                false,
                {
                    setIncludeFirstUse: (_, { includeFirstUse }) => includeFirstUse,
                    applySource: () => false,
                    applyQuery: () => false,
                },
            ],
            seriesSelection: [
                getDotMatrixTileConfig(props.initialConfig).selectedSeries,
                {
                    setSelectedSeries: (_, { selectedSeries }) => selectedSeries,
                    restoreConfig: (_, { config }) => config.selectedSeries,
                    applyQuery: () => [],
                    applySource: () => [],
                },
            ],
            queryEditorOpen: [
                false,
                {
                    editQuery: () => true,
                    cancelQuery: () => false,
                    applyQuery: () => false,
                    applySource: () => false,
                    restoreFailedSave: () => true,
                },
            ],
            queryDraft: [
                DEFAULT_MATRIX_QUERY,
                {
                    setQueryDraft: (_, { query }) => query,
                },
            ],
            mappingDraft: [
                DEFAULT_MATRIX_MAPPING as DotMatrixSourceMapping,
                {
                    setMappingDraft: (_, { mapping }) => mapping,
                },
            ],
            // The view saves optimistically, so a rollback to another source is how a failed save shows up here.
            unconfirmedSource: [
                null as DotMatrixTileSource | null,
                {
                    applyQuery: (_, { source }) => source,
                    applySource: () => null,
                    editQuery: () => null,
                    restoreFailedSave: () => null,
                },
            ],
            // Cancel only needs to reload when a draft or a discarded load replaced the saved source's result.
            savedResultStale: [
                false,
                {
                    editQuery: () => false,
                    loadMatrix: (_, source) => source !== undefined,
                },
            ],
            lastRunQuery: [
                null as string | null,
                {
                    loadMatrix: (_, source) => (source?.kind === 'hogql' ? source.query : null),
                },
            ],
            loadError: [
                null as string | null,
                {
                    loadMatrix: () => null,
                    loadMatrixSuccess: () => null,
                    loadMatrixFailure: (_, { error }) => error,
                },
            ],
        })),
        selectors({
            sourceKind: [
                (s) => [s.config, s.queryEditorOpen],
                (config: DotMatrixTileConfig, editing: boolean): DotMatrixTileSource['kind'] | null =>
                    editing ? 'hogql' : config.source === undefined ? 'usage_metrics' : (config.source?.kind ?? null),
            ],
            activeMapping: [
                (s) => [s.config, s.queryEditorOpen, s.mappingDraft],
                (
                    config: DotMatrixTileConfig,
                    editing: boolean,
                    draft: DotMatrixSourceMapping
                ): DotMatrixSourceMapping =>
                    editing ? draft : config.source?.kind === 'hogql' ? config.source.mapping : DEFAULT_MATRIX_MAPPING,
            ],
            // A saved preset's result stays loaded for Cancel, but it isn't a preview of the SQL being written.
            displayResult: [
                (s) => [s.matrixResult, s.queryEditorOpen],
                (result: DotMatrixTileResult | null, editing: boolean): DotMatrixTileResult | null =>
                    editing && result?.kind !== 'hogql' ? null : result,
            ],
            queryDraftDirty: [
                (s) => [s.config, s.queryDraft, s.mappingDraft],
                (config: DotMatrixTileConfig, query: string, mapping: DotMatrixSourceMapping): boolean => {
                    const saved = config.source?.kind === 'hogql' ? config.source : null
                    return (
                        query !== (saved?.query ?? DEFAULT_MATRIX_QUERY) ||
                        !objectsEqual(mapping, saved?.mapping ?? DEFAULT_MATRIX_MAPPING)
                    )
                },
            ],
            presentation: [
                (s) => [s.displayResult, s.config, s.activeMapping, s.seriesSelection],
                (
                    result: DotMatrixTileResult | null,
                    config: DotMatrixTileConfig,
                    mapping: DotMatrixSourceMapping,
                    selected: string[]
                ) => getDotMatrixTilePresentation(result, selected, mapping, config.weeks),
            ],
            selectedSeries: [
                (s) => [s.seriesSelection, s.presentation],
                (selection: string[], presentation: ReturnType<typeof getDotMatrixTilePresentation>): string[] => {
                    const known = new Set(
                        presentation.matrix.series?.map(({ key }) => key) ??
                            presentation.matrix.data.map(({ series }) => series)
                    )
                    return known.size ? selection.filter((key) => known.has(key)) : selection
                },
            ],
            queryScopeWarning: [
                (s) => [s.queryDraft],
                (query: string): string | null => getMatrixHogQLScopeWarning(query),
            ],
            querySaveError: [
                (s) => [s.config, s.matrixResult, s.queryDraft, s.mappingDraft, s.matrixResultLoading, s.loadError],
                (
                    config: DotMatrixTileConfig,
                    result: DotMatrixTileResult | null,
                    query: string,
                    mapping: DotMatrixSourceMapping,
                    loading: boolean,
                    error: string | null
                ): string | null => {
                    const source = { kind: 'hogql' as const, query, mapping }
                    return getActivityQuerySaveError({
                        scope: 'account',
                        loading,
                        error,
                        source,
                        resultSource: result?.kind === 'hogql' ? { ...source, query: result.query } : null,
                        result: result?.kind === 'hogql' ? result.result : null,
                        config: { ...config, selectedSeries: [], source },
                    })
                },
            ],
        }),
        listeners(({ actions, props, values }) => ({
            chooseSource: ({ kind }) => {
                posthog.capture(AccountsEvents.DotMatrixSourceSelected, { source_kind: kind })
                if (kind === 'hogql') {
                    if (!values.queryEditorOpen) {
                        actions.editQuery()
                    }
                    return
                }
                if (!kind) {
                    return
                }
                const saved = values.config.source === undefined ? { kind: 'usage_metrics' } : values.config.source
                const editing = values.queryEditorOpen
                if (kind === saved?.kind) {
                    if (editing) {
                        confirmDiscard(values.queryDraftDirty, () => actions.cancelQuery())
                    }
                    return
                }
                if (saved?.kind === 'hogql') {
                    LemonDialog.open({
                        title: 'Replace the saved query?',
                        description: 'This tile will stop using its saved SQL, and the SQL will be removed.',
                        primaryButton: {
                            children: 'Replace query',
                            status: 'danger',
                            onClick: () => actions.applySource(kind),
                        },
                        secondaryButton: { children: 'Keep query' },
                    })
                    return
                }
                confirmDiscard(editing && values.queryDraftDirty, () => actions.applySource(kind))
            },
            applySource: () => {
                props.onConfigChange?.({ ...values.config })
                actions.loadMatrix()
            },
            editQuery: () => {
                const saved = values.config.source
                actions.setQueryDraft(saved?.kind === 'hogql' ? saved.query : DEFAULT_MATRIX_QUERY)
                actions.setMappingDraft(saved?.kind === 'hogql' ? saved.mapping : DEFAULT_MATRIX_MAPPING)
                if (saved?.kind !== 'hogql' && values.matrixResultLoading) {
                    actions.loadMatrix(null)
                }
            },
            cancelQuery: () => {
                actions.restoreConfig({
                    ...values.config,
                    selectedSeries: getDotMatrixTileConfig(props.initialConfig).selectedSeries,
                })
                if (values.savedResultStale) {
                    actions.loadMatrix()
                }
            },
            runQuery: () => {
                if (!values.queryDraft.trim() || values.matrixResultLoading) {
                    return
                }
                posthog.capture(AccountsEvents.DotMatrixQueryRun, { source_kind: 'hogql' })
                actions.loadMatrix({ kind: 'hogql', query: values.queryDraft, mapping: values.mappingDraft })
            },
            saveQuery: () => {
                if (!values.querySaveError) {
                    actions.applyQuery({ kind: 'hogql', query: values.queryDraft, mapping: values.mappingDraft })
                }
            },
            applyQuery: () => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSourceConfigured, { source_kind: 'hogql' })
            },
            setMode: ({ mode }) => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSettingChanged, { setting: 'mode', value: mode })
            },
            setWeeks: ({ weeks }) => {
                props.onConfigChange?.({ ...values.config })
                posthog.capture(AccountsEvents.DotMatrixSettingChanged, { setting: 'weeks', value: weeks })
                actions.refreshMatrix()
            },
            // Follows a new date window or account. While editing, it re-runs what was already executed, never unrun SQL.
            setIncludeFirstUse: ({ includeFirstUse }) => {
                posthog.capture(AccountsEvents.DotMatrixSettingChanged, {
                    setting: 'first_use',
                    value: includeFirstUse,
                })
            },
            refreshMatrix: () => {
                if (!values.queryEditorOpen) {
                    actions.loadMatrix()
                    return
                }
                const result = values.matrixResult
                const source = values.config.source
                const query =
                    values.lastRunQuery ??
                    (result?.kind === 'hogql' ? result.query : source?.kind === 'hogql' ? source.query : null)
                if (query !== null) {
                    actions.loadMatrix({ kind: 'hogql', query, mapping: values.mappingDraft })
                } else if (result) {
                    actions.loadMatrix()
                }
            },
            setSelectedSeries: ({ selectedSeries }) => {
                posthog.capture(AccountsEvents.DotMatrixSeriesSelected, { selected_count: selectedSeries.length })
            },
            retry: () => {
                posthog.capture(AccountsEvents.DotMatrixRetried)
                if (values.queryEditorOpen) {
                    actions.runQuery()
                } else {
                    actions.loadMatrix()
                }
            },
            loadMatrixSuccess: ({ matrixResult }) => {
                if (values.queryEditorOpen && matrixResult?.kind === 'hogql') {
                    const columns = (matrixResult.result.columns ?? []).filter(
                        (name): name is string => typeof name === 'string'
                    )
                    actions.setMappingDraft(inferHogQLMatrixMapping(columns, values.mappingDraft))
                }
            },
            loadMatrixFailure: ({ errorObject }) => {
                posthog.capture(AccountsEvents.DotMatrixLoadFailed, {
                    failure_type: errorObject?.status === 403 ? 'denied' : 'request',
                    source_kind: values.sourceKind,
                })
            },
        })),
        propsChanged(({ actions, props, values }, previousProps) => {
            const next = getDotMatrixTileConfig(props.initialConfig)
            let queryChanged = false
            let saveFailed = false
            if (
                !objectsEqual(next, getDotMatrixTileConfig(previousProps.initialConfig)) &&
                !objectsEqual(next, values.config)
            ) {
                const sourceChanged = !objectsEqual(next.source, values.config.source)
                queryChanged = next.weeks !== values.config.weeks || sourceChanged
                saveFailed =
                    sourceChanged && !!values.unconfirmedSource && !objectsEqual(next.source, values.unconfirmedSource)
                actions.restoreConfig(next)
            }
            if (saveFailed) {
                actions.restoreFailedSave()
                return
            }
            if (
                props.accountId !== previousProps.accountId ||
                props.externalId !== previousProps.externalId ||
                queryChanged
            ) {
                actions.refreshMatrix()
            }
        }),
        afterMount(({ actions }) => {
            posthog.capture(AccountsEvents.DotMatrixViewed)
            actions.loadMatrix()
        }),
    ])
