import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { performQuery } from '~/queries/query'
import {
    NodeKind,
    type AccountAgentActivityQuery,
    type AccountAgentActivityResult,
} from '~/queries/schema/schema-general'

import { CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS } from '../../constants'
import { getTileString, type AccountViewTileLogicProps } from './accountViewTileConfig'
import { getAccountWidgetWeeks, type AccountWidgetWeeks } from './accountWidgetWeeks'
import { AccountsEvents } from './constants'

export interface AccountAgentActivityLogicProps extends AccountViewTileLogicProps {
    accountId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountAgentActivityLogicValues {
    loadFailed: boolean
    result: AccountAgentActivityResult | null
    resultLoading: boolean
    weeks: 4 | 8 | 12 | 26
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountAgentActivityLogicActions {
    loadResult: (_: void) => void
    loadResultFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadResultSuccess: (
        result: AccountAgentActivityResult,
        payload?: void
    ) => {
        result: AccountAgentActivityResult
        payload?: void
    }
    setWeeks: (weeks: AccountWidgetWeeks) => {
        weeks: 4 | 8 | 12 | 26
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountAgentActivityLogicMeta {
    key: string
}

export type accountAgentActivityLogicType = MakeLogicType<
    accountAgentActivityLogicValues,
    accountAgentActivityLogicActions,
    AccountAgentActivityLogicProps,
    accountAgentActivityLogicMeta
>

export const accountAgentActivityLogic = kea<accountAgentActivityLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountAgentActivityLogic', key]),
    props({} as AccountAgentActivityLogicProps),
    key((props) => `${props.accountId}:${props.instanceId ?? 'default'}`),
    actions({
        setWeeks: (weeks: AccountWidgetWeeks) => ({ weeks }),
    }),
    reducers(({ props }) => ({
        weeks: [
            getAccountWidgetWeeks(getTileString(props.initialConfig, 'weeks')),
            {
                setWeeks: (_, { weeks }) => weeks,
            },
        ],
    })),
    loaders(({ props, values }) => ({
        result: [
            null as AccountAgentActivityResult | null,
            {
                loadResult: async (_: void, breakpoint) => {
                    await breakpoint(10)
                    const response = await performQuery<AccountAgentActivityQuery>({
                        kind: NodeKind.AccountAgentActivityQuery,
                        tags: CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS,
                        accountId: props.accountId,
                        weeks: values.weeks,
                    })
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),
    reducers({
        loadFailed: [
            false,
            {
                loadResult: () => false,
                loadResultSuccess: () => false,
                loadResultFailure: () => true,
            },
        ],
    }),
    listeners(({ actions, props }) => ({
        setWeeks: ({ weeks }) => {
            props.onConfigChange?.({ weeks: String(weeks) })
            posthog.capture(AccountsEvents.AgentActivityWeeksChanged, { weeks })
            actions.loadResult()
        },
        loadResultFailure: ({ errorObject }) => {
            posthog.captureException(errorObject, { scope: 'accountAgentActivityLogic.loadResult' })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadResult()
    }),
])
