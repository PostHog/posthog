// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountSummariesLogicMeta {
    key: string
}

export type accountSummariesLogicType = MakeLogicType<
    accountSummariesLogicValues,
    accountSummariesLogicActions,
    AccountSummariesLogicProps,
    accountSummariesLogicMeta
>

export const accountSummariesLogic = kea<accountSummariesLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountSummariesLogic', key]),
    props({} as AccountSummariesLogicProps),
    key((props) => props.accountId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        setCadence: (cadence: SlackSummaryCadenceEnumApi | null) => ({ cadence }),
        setCadenceSuccess: (cadence: SlackSummaryCadenceEnumApi | null) => ({ cadence }),
        setCadenceFailure: true,
        startFirstSummaryPolling: true,
        stopFirstSummaryPolling: true,
        toggleSummaryExpanded: (summaryId: string) => ({ summaryId }),
    }),
    loaders(({ props, values }) => ({
        summariesResult: [
            NOT_LOADED,
            {
                loadSummaries: async (): Promise<AccountSummariesResult> => {
                    try {
                        const [account, page] = await Promise.all([
                            accountsRetrieve(String(values.currentTeamId), props.accountId),
                            accountsSummariesList(String(values.currentTeamId), props.accountId, {
                                limit: SUMMARIES_PAGE_SIZE,
                                offset: 0,
                            }),
                        ])
                        return {
                            summaries: page.results,
                            totalCount: page.count,
                            slackChannelId: account.properties?.slack_channel_id ?? null,
                            cadence: account.slack_summary_cadence ?? null,
                        }
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountSummariesLogic.loadSummaries',
                        })
                        return { ...NOT_LOADED, loadFailed: true }
                    }
                },
                loadSummariesPage: async ({ page }): Promise<AccountSummariesResult> => {
                    const current = values.summariesResult
                    try {
                        const result = await accountsSummariesList(String(values.currentTeamId), props.accountId, {
                            limit: SUMMARIES_PAGE_SIZE,
                            offset: (page - 1) * SUMMARIES_PAGE_SIZE,
                        })
                        return {
                            ...current,
                            summaries: result.results,
                            totalCount: result.count,
                        }
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountSummariesLogic.loadSummariesPage',
                        })
                        lemonToast.error("Couldn't load that page of summaries. Try again.")
                        return current
                    }
                },
            },
        ],
    })),
    reducers({
        summariesResult: {
            setCadenceSuccess: (state: AccountSummariesResult, { cadence }) => ({ ...state, cadence }),
        },
        cadenceSaving: [
            false,
            {
                setCadence: () => true,
                setCadenceSuccess: () => false,
                setCadenceFailure: () => false,
            },
        ],
        generatingFirstSummary: [
            false,
            {
                startFirstSummaryPolling: () => true,
                stopFirstSummaryPolling: () => false,
            },
        ],
        page: [
            1,
            {
                loadSummaries: () => 1,
                loadSummariesPage: (_: number, { page }: { page: number }) => page,
            },
        ],
        expandedSummaryIds: [
            {} as Record<string, boolean>,
            {
                toggleSummaryExpanded: (state: Record<string, boolean>, { summaryId }: { summaryId: string }) => ({
                    ...state,
                    [summaryId]: !state[summaryId],
                }),
            },
        ],
    }),
    listeners(({ actions, cache, props, values }) => ({
        startFirstSummaryPolling: () => {
            if ((backfillDeadlines.get(props.accountId) ?? 0) <= Date.now()) {
                actions.stopFirstSummaryPolling()
                return
            }
            cache.lastSeenCount = values.summariesResult.totalCount
            cache.lastChangeAt = Date.now()
            cache.disposables.add(() => {
                const intervalId = setInterval(() => actions.loadSummaries(), FIRST_SUMMARY_POLL_INTERVAL_MS)
                return () => clearInterval(intervalId)
            }, 'firstSummaryPoll')
        },
        stopFirstSummaryPolling: () => {
            backfillDeadlines.delete(props.accountId)
            cache.disposables.dispose('firstSummaryPoll')
        },
        loadSummariesSuccess: ({ summariesResult }) => {
            if (!values.generatingFirstSummary) {
                return
            }
            // totalCount, not the page length: a daily backfill writes up to 7 summaries and a page holds 5.
            const landed = summariesResult.totalCount
            if (landed !== cache.lastSeenCount) {
                cache.lastSeenCount = landed
                cache.lastChangeAt = Date.now()
                return
            }
            // Wall-clock, because the disposables plugin suspends this interval on a hidden
            // tab: counting polls would stretch the wait by however long the user is away.
            const quietFor = Date.now() - (cache.lastChangeAt ?? 0)
            const expired = Date.now() >= (backfillDeadlines.get(props.accountId) ?? 0)
            if (expired || (landed > 0 && quietFor >= FIRST_SUMMARY_QUIET_MS)) {
                actions.stopFirstSummaryPolling()
            }
        },
        toggleSummaryExpanded: ({ summaryId }) => {
            if (values.expandedSummaryIds[summaryId]) {
                posthog.capture(AccountsEvents.SummaryExpanded)
            }
        },
        loadSummariesPage: ({ page }) => {
            posthog.capture(AccountsEvents.SummariesPageChanged, { page })
        },
        setCadence: async ({ cadence }) => {
            // Only an off-to-on switch backfills, so only that one starts a wait.
            const wasOff = !values.summariesResult.cadence
            try {
                await accountsPartialUpdate(String(values.currentTeamId), props.accountId, {
                    slack_summary_cadence: cadence,
                })
                actions.setCadenceSuccess(cadence)
                posthog.capture(AccountsEvents.SummaryCadenceChanged, { cadence: cadence ?? 'off' })
                if (cadence && wasOff && !values.summariesResult.summaries?.length) {
                    backfillDeadlines.set(props.accountId, Date.now() + FIRST_SUMMARY_POLL_TIMEOUT_MS)
                    actions.startFirstSummaryPolling()
                } else if (!cadence) {
                    actions.stopFirstSummaryPolling()
                }
            } catch (error) {
                posthog.captureException(error as Error, {
                    scope: 'accountSummariesLogic.setCadence',
                })
                lemonToast.error("Couldn't update the summary cadence. Try again.")
                actions.setCadenceFailure()
            }
        },
    })),
    afterMount(({ actions, props }) => {
        actions.loadSummaries()
        if ((backfillDeadlines.get(props.accountId) ?? 0) > Date.now()) {
            actions.startFirstSummaryPolling()
        }
    }),
])
