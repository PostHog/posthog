import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'

import {
    accountsPartialUpdate,
    accountsRetrieve,
    accountsSummariesList,
} from 'products/customer_analytics/frontend/generated/api'
import {
    AccountChannelSummaryApi,
    SlackSummaryCadenceEnumApi,
} from 'products/customer_analytics/frontend/generated/api.schemas'

import { AccountsEvents } from './constants'

export interface AccountSummariesLogicProps {
    accountId: string
}

// Outcomes: a null `slackChannelId` means no channel is linked (the tab points at linking one);
// `summaries` is the current page, `totalCount` the server-side total (drives pagination).
// `loadFailed` is set when the load itself errored, so the view shows a "couldn't load" state
// rather than hanging on the skeleton.
export interface AccountSummariesResult {
    summaries: AccountChannelSummaryApi[] | null
    totalCount: number
    slackChannelId: string | null
    cadence: SlackSummaryCadenceEnumApi | null
    loadFailed?: boolean
}

// Identity used as a "not loaded yet" sentinel by the view — every loaded outcome returns a fresh object.
export const NOT_LOADED: AccountSummariesResult = {
    summaries: null,
    totalCount: 0,
    slackChannelId: null,
    cadence: null,
}

export const SUMMARIES_PAGE_SIZE = 5

export const FIRST_SUMMARY_POLL_INTERVAL_MS = 15_000
export const FIRST_SUMMARY_POLL_TIMEOUT_MS = 5 * 60_000
// A backfilled period with no messages writes no summary, so there is no count to wait for.
export const FIRST_SUMMARY_QUIET_MS = 90_000

// Module state, not logic state: this tab unmounts when its account row collapses, and the
// backfill it waits on keeps running server-side.
const backfillDeadlines = new Map<string, number>()

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountSummariesLogicValues {
    currentTeamId: number | null // teamLogic
    cadenceSaving: boolean
    expandedSummaryIds: Record<string, boolean>
    generatingFirstSummary: boolean
    page: number
    summariesResult: AccountSummariesResult
    summariesResultLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
