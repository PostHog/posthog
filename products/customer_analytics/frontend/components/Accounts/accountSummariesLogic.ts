import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'

import {
    accountsPartialUpdate,
    accountsRetrieve,
    accountsSummariesList,
} from 'products/customer_analytics/frontend/generated/api'
import {
    AccountChannelSummaryApi,
    SlackSummaryCadenceEnumApi,
} from 'products/customer_analytics/frontend/generated/api.schemas'

import { AccountsEvents } from './constants'

export interface AccountSummariesLogicProps {
    accountId: string
}

// Outcomes: a null `slackChannelId` means no channel is linked (the tab points at linking one);
// `summaries` is the loaded page(s), `totalCount` the server-side total (drives "Load more").
// `loadFailed` is set when the load itself errored, so the view shows a "couldn't load" state
// rather than hanging on the skeleton.
export interface AccountSummariesResult {
    summaries: AccountChannelSummaryApi[] | null
    totalCount: number
    slackChannelId: string | null
    cadence: SlackSummaryCadenceEnumApi | null
    loadFailed?: boolean
}

// Identity used as a "not loaded yet" sentinel by the view — every loaded outcome returns a fresh object.
export const NOT_LOADED: AccountSummariesResult = {
    summaries: null,
    totalCount: 0,
    slackChannelId: null,
    cadence: null,
}

export const SUMMARIES_PAGE_SIZE = 10

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountSummariesLogicValues {
    currentTeamId: number | null // teamLogic
    cadenceSaving: boolean
    summariesResult: AccountSummariesResult
    summariesResultLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountSummariesLogicActions {
    loadMoreSummaries: () => any
    loadMoreSummariesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadMoreSummariesSuccess: (
        summariesResult: AccountSummariesResult,
        payload?: any
    ) => {
        summariesResult: AccountSummariesResult
        payload?: any
    }
    loadSummaries: () => any
    loadSummariesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSummariesSuccess: (
        summariesResult: AccountSummariesResult,
        payload?: any
    ) => {
        summariesResult: AccountSummariesResult
        payload?: any
    }
    setCadence: (cadence: SlackSummaryCadenceEnumApi | null) => {
        cadence: SlackSummaryCadenceEnumApi | null
    }
    setCadenceFailure: () => {
        value: true
    }
    setCadenceSuccess: (cadence: SlackSummaryCadenceEnumApi | null) => {
        cadence: SlackSummaryCadenceEnumApi | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountSummariesLogicMeta {
    key: string
}

export type accountSummariesLogicType = MakeLogicType<
    accountSummariesLogicValues,
    accountSummariesLogicActions,
    AccountSummariesLogicProps,
    accountSummariesLogicMeta
>

export const accountSummariesLogic = kea<accountSummariesLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountSummariesLogic', key]),
    props({} as AccountSummariesLogicProps),
    key((props) => props.accountId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        setCadence: (cadence: SlackSummaryCadenceEnumApi | null) => ({ cadence }),
        setCadenceSuccess: (cadence: SlackSummaryCadenceEnumApi | null) => ({ cadence }),
        setCadenceFailure: true,
    }),
    loaders(({ props, values }) => ({
        summariesResult: [
            NOT_LOADED,
            {
                loadSummaries: async (): Promise<AccountSummariesResult> => {
                    try {
                        const [account, page] = await Promise.all([
                            accountsRetrieve(String(values.currentTeamId), props.accountId),
                            accountsSummariesList(String(values.currentTeamId), props.accountId, {
                                limit: SUMMARIES_PAGE_SIZE,
                                offset: 0,
                            }),
                        ])
                        return {
                            summaries: page.results,
                            totalCount: page.count,
                            slackChannelId: account.properties?.slack_channel_id ?? null,
                            cadence: account.slack_summary_cadence ?? null,
                        }
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountSummariesLogic.loadSummaries',
                        })
                        return { ...NOT_LOADED, loadFailed: true }
                    }
                },
                loadMoreSummaries: async (): Promise<AccountSummariesResult> => {
                    const current = values.summariesResult
                    try {
                        const page = await accountsSummariesList(String(values.currentTeamId), props.accountId, {
                            limit: SUMMARIES_PAGE_SIZE,
                            offset: current.summaries?.length ?? 0,
                        })
                        return {
                            ...current,
                            summaries: [...(current.summaries ?? []), ...page.results],
                            totalCount: page.count,
                        }
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountSummariesLogic.loadMoreSummaries',
                        })
                        lemonToast.error("Couldn't load more summaries. Try again.")
                        return current
                    }
                },
            },
        ],
    })),
    reducers({
        summariesResult: {
            setCadenceSuccess: (state: AccountSummariesResult, { cadence }) => ({ ...state, cadence }),
        },
        cadenceSaving: [
            false,
            {
                setCadence: () => true,
                setCadenceSuccess: () => false,
                setCadenceFailure: () => false,
            },
        ],
    }),
    listeners(({ actions, props, values }) => ({
        setCadence: async ({ cadence }) => {
            try {
                await accountsPartialUpdate(String(values.currentTeamId), props.accountId, {
                    slack_summary_cadence: cadence,
                })
                actions.setCadenceSuccess(cadence)
                posthog.capture(AccountsEvents.SummaryCadenceChanged, { cadence: cadence ?? 'off' })
            } catch (error) {
                posthog.captureException(error as Error, {
                    scope: 'accountSummariesLogic.setCadence',
                })
                lemonToast.error("Couldn't update the summary cadence. Try again.")
                actions.setCadenceFailure()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSummaries()
    }),
])
