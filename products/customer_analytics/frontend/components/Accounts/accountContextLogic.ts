export type AccountContextResult =
    | { status: 'loaded'; context: AccountContext }
    | { status: 'failed' }
    | { status: 'no_access' }
    | { status: 'unreadable' }
    | { status: 'not_configured' }
    | { status: 'no_external_id' }

const LOAD_SCOPE = 'accountContextLogic.loadContext'

function requestFailure(error: unknown): AccountContextResult {
    const status = (error as { status?: unknown } | null)?.status
    if (status === 403 || status === 404) {
        posthog.capture(AccountsEvents.ContextLoadFailed, { reason: 'no_access' })
        return { status: 'no_access' }
    }
    posthog.captureException(new Error('Account context request failed'), {
        scope: LOAD_SCOPE,
        status: typeof status === 'number' ? status : null,
    })
    posthog.capture(AccountsEvents.ContextLoadFailed, { reason: 'error' })
    return { status: 'failed' }
}

function loadedResult(response: EndpointRunResponseApi): AccountContextResult {
    const missingColumns = missingContextColumns(response)
    if (missingColumns.length) {
        posthog.captureException(new Error('Account context response is missing columns'), {
            scope: LOAD_SCOPE,
            missing_columns: missingColumns,
        })
        posthog.capture(AccountsEvents.ContextLoadFailed, { reason: 'unreadable' })
        return { status: 'unreadable' }
    }
    const context = parseAccountContext(response)
    posthog.capture(AccountsEvents.ContextLoaded, {
        fact_count: context.facts.length,
        signal_count: context.signals.length,
        thread_count: context.threads.length,
    })
    return { status: 'loaded', context }
}

