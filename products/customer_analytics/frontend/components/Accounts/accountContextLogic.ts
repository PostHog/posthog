export type accountContextLogicType = MakeLogicType<
    accountContextLogicValues,
    accountContextLogicActions,
    AccountContextLogicProps,
    accountContextLogicMeta
>

export const accountContextLogic = kea<accountContextLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountContextLogic', key]),
    props({} as AccountContextLogicProps),
    key((props) => `${props.accountId}:${props.instanceId ?? 'default'}`),
    actions({
        setFactConfidence: (confidence: FactConfidence) => ({ confidence }),
        setFactSearch: (search: string) => ({ search }),
        setTopicFilter: (topic: string | null) => ({ topic }),
        setAuthorFilter: (author: string | null) => ({ author }),
        setSourceFilter: (source: string | null) => ({ source }),
        setRecheckOnly: (recheckOnly: boolean) => ({ recheckOnly }),
        setSignalState: (signalState: SignalState) => ({ signalState }),
    }),
    loaders(({ props }) => ({
        contextResult: [
            null as AccountContextResult | null,
            {
                loadContext: async (_: void, breakpoint): Promise<AccountContextResult> => {
                    const source = parseContextSource(
                        getFeatureFlagPayload(FEATURE_FLAGS.CUSTOMER_ANALYTICS_CONTEXT_PANE)
                    )
                    if (!source || !props.externalId) {
                        return { status: 'not_configured' }
                    }
                    try {
                        const response = await endpointsRunCreate(source.projectId, source.endpoint, {
                            variables: { [source.accountVariable]: props.externalId },
                        })
                        breakpoint()
                        const context = parseAccountContext(response)
                        posthog.capture(AccountsEvents.ContextLoaded, {
                            fact_count: context.facts.length,
                            signal_count: context.signals.length,
                            thread_count: context.threads.length,
                        })
                        return { status: 'loaded', context }
                    } catch (error) {
                        breakpoint()
                        posthog.captureException(error as Error, { scope: 'accountContextLogic.loadContext' })
                        posthog.capture(AccountsEvents.ContextLoadFailed)
                        return { status: 'failed' }
                    }
                },
            },
        ],
    })),
    reducers({
        factConfidence: ['confirmed' as FactConfidence, { setFactConfidence: (_, { confidence }) => confidence }],
        factSearch: ['', { setFactSearch: (_, { search }) => search }],
        topicFilter: [null as string | null, { setTopicFilter: (_, { topic }) => topic }],
        authorFilter: [null as string | null, { setAuthorFilter: (_, { author }) => author }],
        sourceFilter: [null as string | null, { setSourceFilter: (_, { source }) => source }],
        recheckOnly: [false, { setRecheckOnly: (_, { recheckOnly }) => recheckOnly }],
        signalState: ['open' as SignalState, { setSignalState: (_, { signalState }) => signalState }],
    }),
    selectors({
        context: [
            (s) => [s.contextResult],
            (contextResult: AccountContextResult | null): AccountContext | null =>
                contextResult?.status === 'loaded' ? contextResult.context : null,
        ],
        summary: [
            (s) => [s.context],
            (context: AccountContext | null): AccountContextSummary | null =>
                context ? summarizeContext(context) : null,
        ],
        confidenceCounts: [
            (s) => [s.context],
            (context: AccountContext | null): Record<FactConfidence, number> => ({
                confirmed: context?.facts.filter((fact) => fact.confirmed).length ?? 0,
                inferred: context?.facts.filter((fact) => !fact.confirmed).length ?? 0,
            }),
        ],
        filterOptions: [
            (s) => [s.context],
            (context: AccountContext | null) => factFilterOptions(context?.facts ?? []),
        ],
        visibleFacts: [
            (s) => [
                s.context,
                s.factConfidence,
                s.factSearch,
                s.topicFilter,
                s.authorFilter,
                s.sourceFilter,
                s.recheckOnly,
            ],
            (
                context: AccountContext | null,
                confidence: FactConfidence,
                search: string,
                topic: string | null,
                author: string | null,
                source: string | null,
                recheckOnly: boolean
            ): AccountContextFact[] =>
                filterFacts(context?.facts ?? [], { confidence, search, topic, author, source, recheckOnly }),
        ],
        visibleSignals: [
            (s) => [s.context, s.signalState],
            (context: AccountContext | null, signalState: SignalState): AccountContextSignal[] =>
                (context?.signals ?? []).filter((signal) => signal.open === (signalState === 'open')),
        ],
    }),
    afterMount(({ actions }) => {
        posthog.capture(AccountsEvents.ContextViewed)
        actions.loadContext()
    }),
])
