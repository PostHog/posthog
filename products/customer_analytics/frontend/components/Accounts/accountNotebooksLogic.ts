export const accountNotebooksLogic = kea<accountNotebooksLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountNotebooksLogic', key]),
    props({} as AccountNotebooksLogicProps),
    key((props) => `${props.accountId}:${props.instanceId ?? 'default'}`),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [notebookPanelLogic, ['selectNotebook']],
    })),
    actions({
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        setSorting: (sorting: Sorting | null) => ({ sorting }),
        setPage: (page: number) => ({ page }),
        setTagsFilter: (tags: string[]) => ({ tags }),
        setCreatedByFilter: (userIds: number[]) => ({ userIds }),
        // Replaces search, tags, author and sort at once (saved views), so the list loads a single time.
        applyViewState: (viewState: AccountNotesViewState) => ({ viewState }),
        createNote: true,
        updateNotebook: (shortId: string, updates: PatchedAccountNotebookUpdateApi) => ({ shortId, updates }),
    }),
    loaders(({ props, values }) => ({
        notebooksResponse: [
            null as PaginatedAccountNotebookListApi | null,
            {
                loadNotebooks: async (_ = null, breakpoint) => {
                    const projectId = String(values.currentTeamId)
                    try {
                        const response = await accountsNotebooksList(projectId, props.accountId, {
                            limit: NOTES_PER_PAGE,
                            offset: (values.page - 1) * NOTES_PER_PAGE,
                            search: values.searchTerm.trim() || undefined,
                            ordering: sortingToOrdering(values.sorting),
                            tags: values.tagsFilter.length ? JSON.stringify(values.tagsFilter) : undefined,
                            created_by: values.createdByFilter.length ? values.createdByFilter : undefined,
                        })
                        breakpoint()
                        return response
                    } catch (error) {
                        if (!isBreakpoint(error as Error)) {
                            posthog.captureException(error as Error, {
                                scope: 'accountNotebooksLogic.loadNotebooks',
                            })
                            lemonToast.error('Failed to load account notes')
                        }
                        throw error
                    }
                },
            },
        ],
        createdNote: [
            null as AccountNotebookApi | null,
            {
                createNote: async () => {
                    const projectId = String(values.currentTeamId)
                    try {
                        return await accountsNotebooksCreate(projectId, props.accountId, {
                            content: defaultNotebookContent(),
                        })
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountNotebooksLogic.createNote',
                        })
                        lemonToast.error('Failed to create note')
                        throw error
                    }
                },
            },
        ],
        updatedNotebook: [
            null as AccountNotebookApi | null,
            {
                updateNotebook: async ({
                    shortId,
                    updates,
                }: {
                    shortId: string
                    updates: PatchedAccountNotebookUpdateApi
                }) => {
                    const projectId = String(values.currentTeamId)
                    try {
                        return await accountsNotebooksPartialUpdate(projectId, props.accountId, shortId, updates)
                    } catch (error) {
                        posthog.captureException(error as Error, {
                            scope: 'accountNotebooksLogic.updateNotebook',
                        })
                        lemonToast.error('Failed to update note')
                        throw error
                    }
                },
            },
        ],
    })),
    reducers(({ props }) => ({
        searchTerm: [
            getTileString(props.initialConfig, 'searchTerm'),
            {
                setSearchTerm: (_, { searchTerm }) => searchTerm,
                applyViewState: (_, { viewState }) => viewState.filters.search,
            },
        ],
        sorting: [
            getInitialSorting(props.initialConfig),
            {
                setSorting: (_, { sorting }) => sorting,
                applyViewState: (_, { viewState }) => viewOrderingToSorting(viewState.ordering),
            },
        ],
        page: [1, { setPage: (_, { page }) => page }],
        tagsFilter: [
            [] as string[],
            {
                setTagsFilter: (_, { tags }) => tags,
                applyViewState: (_, { viewState }) => viewState.filters.tags,
            },
        ],
        createdByFilter: [
            [] as number[],
            {
                setCreatedByFilter: (_, { userIds }) => userIds,
                applyViewState: (_, { viewState }) => viewState.filters.created_by,
            },
        ],
        passthroughViewFilters: [
            EMPTY_PASSTHROUGH_FILTERS,
            {
                applyViewState: (_, { viewState }) => ({
                    assigned_to: viewState.filters.assigned_to,
                    account_id: viewState.filters.account_id,
                    account_name: viewState.filters.account_name,
                }),
            },
        ],
        notebooksResponse: [
            null as PaginatedAccountNotebookListApi | null,
            {
                // Patch the row in place so tag edits don't flash a full reload.
                updateNotebookSuccess: (state, { updatedNotebook }) =>
                    state
                        ? {
                              ...state,
                              results: state.results.map((notebook) =>
                                  notebook.short_id === updatedNotebook.short_id ? updatedNotebook : notebook
                              ),
                          }
                        : state,
            },
        ],
        updatingShortId: [
            null as string | null,
            {
                updateNotebook: (_, { shortId }) => shortId,
                updateNotebookSuccess: () => null,
                updateNotebookFailure: () => null,
            },
        ],
    })),
    selectors(({ actions }) => ({
        notebooks: [
            (s) => [s.notebooksResponse],
            (response: PaginatedAccountNotebookListApi | null): AccountNotebookApi[] | null =>
                response?.results ?? null,
        ],
        notebooksCount: [
            (s) => [s.notebooksResponse],
            (response: PaginatedAccountNotebookListApi | null): number => response?.count ?? 0,
        ],
        pagination: [
            (s) => [s.page, s.notebooksCount],
            (page: number, count: number): PaginationManual => ({
                controlled: true,
                pageSize: NOTES_PER_PAGE,
                currentPage: page,
                useUrl: false,
                entryCount: count,
                onBackward: () => actions.setPage(page - 1),
                onForward: () => actions.setPage(page + 1),
            }),
        ],
        viewState: [
            (s) => [s.searchTerm, s.tagsFilter, s.createdByFilter, s.sorting, s.passthroughViewFilters],
            (
                searchTerm: string,
                tagsFilter: string[],
                createdByFilter: number[],
                sorting: Sorting | null,
                passthroughViewFilters: PassthroughViewFilters
            ): AccountNotesViewState => ({
                filters: {
                    ...EMPTY_NOTES_VIEW_STATE.filters,
                    ...passthroughViewFilters,
                    search: searchTerm,
                    tags: tagsFilter,
                    created_by: createdByFilter,
                },
                ordering: sortingToViewOrdering(sorting),
            }),
        ],
        // What "All notes" goes back to on this tab: no filters, newest first (this tab's own default sort).
        defaultViewState: [
            () => [],
            (): AccountNotesViewState => ({
                filters: EMPTY_NOTES_VIEW_STATE.filters,
                ordering: sortingToViewOrdering(DEFAULT_NOTES_SORTING),
            }),
        ],
    })),
    listeners(({ actions, props, values }) => ({
        setSearchTerm: async (_, breakpoint) => {
            await breakpoint(300)
            props.onConfigChange?.({ searchTerm: values.searchTerm, sorting: values.sorting })
            posthog.capture(AccountsEvents.NotesSearched, {
                has_query: values.searchTerm.trim().length > 0,
                query_length: values.searchTerm.trim().length,
            })
            actions.setPage(1)
        },
        setSorting: ({ sorting }) => {
            props.onConfigChange?.({ searchTerm: values.searchTerm, sorting: values.sorting })
            posthog.capture(AccountsEvents.NotesSorted, {
                column: sorting?.columnKey ?? null,
                direction: sorting ? (sorting.order === -1 ? 'desc' : 'asc') : 'cleared',
            })
            actions.setPage(1)
        },
        setTagsFilter: () => {
            posthog.capture(AccountsEvents.NotesFiltered, {
                filter_type: 'tag',
                tag_count: values.tagsFilter.length,
                is_cleared: values.tagsFilter.length === 0,
            })
            actions.setPage(1)
        },
        setCreatedByFilter: () => {
            posthog.capture(AccountsEvents.NotesFiltered, {
                filter_type: 'created_by',
                user_count: values.createdByFilter.length,
                is_cleared: values.createdByFilter.length === 0,
            })
            actions.setPage(1)
        },
        applyViewState: () => {
            props.onConfigChange?.({ searchTerm: values.searchTerm, sorting: values.sorting })
            actions.setPage(1)
        },
        setPage: () => {
            actions.loadNotebooks()
        },
        createNoteSuccess: ({ createdNote }) => {
            if (!createdNote) {
                return
            }
            posthog.capture(AccountsEvents.NoteCreated, { notebook_short_id: createdNote.short_id })
            actions.selectNotebook(createdNote.short_id)
            // A new note sorts to page 1 (default -created_at); reset there so it's visible in the table.
            actions.setPage(1)
        },
        updateNotebookSuccess: ({ updatedNotebook, payload }) => {
            posthog.capture(AccountsEvents.NoteUpdated, {
                notebook_short_id: updatedNotebook.short_id,
                fields: Object.keys(payload?.updates ?? {}),
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadNotebooks()
    }),
])
