export const NOTES_PER_PAGE = 5

export const DEFAULT_NOTES_SORTING: Sorting = { columnKey: 'created_at', order: -1 }

// Columns the per-account notebooks endpoint can order by.
const SORTABLE_COLUMNS = new Set(['created_at', 'created_by', 'last_modified_at', 'title'])

// The account and "My accounts" filters pick accounts, so they mean nothing inside one account. They are echoed
// back in viewState so an applied view does not read as modified, and the view summary says they apply elsewhere.
export type PassthroughViewFilters = Pick<AccountNotesViewFilters, 'assigned_to' | 'account_id' | 'account_name'>

const EMPTY_PASSTHROUGH_FILTERS: PassthroughViewFilters = {
    assigned_to: [],
    account_id: null,
    account_name: null,
}

export interface AccountNotebooksLogicProps extends AccountViewTileLogicProps {
    accountId: string
}

function getInitialSorting(config: AccountViewTileConfig | undefined): Sorting | null {
    const sorting = getTileRecord(config, 'sorting')
    return typeof sorting?.columnKey === 'string' && (sorting.order === 1 || sorting.order === -1)
        ? (sorting as unknown as Sorting)
        : DEFAULT_NOTES_SORTING
}

// Maps the table's sorting state onto the backend's whitelisted `ordering` param.
function sortingToOrdering(sorting: Sorting | null): string | undefined {
    if (!sorting) {
        return undefined
    }
    return sorting.order === -1 ? `-${sorting.columnKey}` : sorting.columnKey
}

// Saved views store the team-wide ordering; a sort the team list does not know falls back to newest first.
export function sortingToViewOrdering(sorting: Sorting | null): AccountNotesListOrdering {
    const ordering = sortingToOrdering(sorting)
    return isAccountNotesListOrdering(ordering) ? ordering : '-created_at'
}

export function viewOrderingToSorting(ordering: AccountNotesListOrdering): Sorting {
    const sorting = orderingToSorting(ordering)
    return SORTABLE_COLUMNS.has(sorting.columnKey) ? sorting : DEFAULT_NOTES_SORTING
}

