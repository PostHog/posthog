import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { performQuery } from '~/queries/query'
import { NodeKind, type AccountTopPagesQuery, type AccountTopPagesResult } from '~/queries/schema/schema-general'

import { CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS } from '../../constants'
import { getTileString, type AccountViewTileLogicProps } from './accountViewTileConfig'
import { getAccountWidgetWeeks, type AccountWidgetWeeks } from './accountWidgetWeeks'
import { AccountsEvents } from './constants'

export interface AccountTopPagesLogicProps extends AccountViewTileLogicProps {
    accountId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountTopPagesLogicValues {
    config: Record<string, string>
    loadFailed: boolean
    productKey: string | null
    result: AccountTopPagesResult | null
    resultLoading: boolean
    weeks: 4 | 8 | 12 | 26
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountTopPagesLogicActions {
    loadResult: (_: void) => void
    loadResultFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadResultSuccess: (
        result: AccountTopPagesResult,
        payload?: void
    ) => {
        result: AccountTopPagesResult
        payload?: void
    }
    setProductKey: (productKey: string | null) => {
        productKey: string | null
    }
    setWeeks: (weeks: AccountWidgetWeeks) => {
        weeks: 4 | 8 | 12 | 26
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountTopPagesLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        config: (weeks: 4 | 8 | 12 | 26, productKey: string | null) => Record<string, string>
    }
}

export type accountTopPagesLogicType = MakeLogicType<
    accountTopPagesLogicValues,
    accountTopPagesLogicActions,
    AccountTopPagesLogicProps,
    accountTopPagesLogicMeta
>

export const accountTopPagesLogic = kea<accountTopPagesLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountTopPagesLogic', key]),
    props({} as AccountTopPagesLogicProps),
    key((props) => `${props.accountId}:${props.instanceId ?? 'default'}`),
    actions({
        setWeeks: (weeks: AccountWidgetWeeks) => ({ weeks }),
        setProductKey: (productKey: string | null) => ({ productKey }),
    }),
    reducers(({ props }) => ({
        weeks: [
            getAccountWidgetWeeks(getTileString(props.initialConfig, 'weeks')),
            {
                setWeeks: (_, { weeks }) => weeks,
            },
        ],
        // The product list comes with the result, so an unknown saved key shows all pages until it loads.
        productKey: [
            (getTileString(props.initialConfig, 'productKey') || null) as string | null,
            {
                setProductKey: (_, { productKey }) => productKey,
            },
        ],
    })),
    loaders(({ props, values }) => ({
        result: [
            null as AccountTopPagesResult | null,
            {
                loadResult: async (_: void, breakpoint) => {
                    await breakpoint(10)
                    const response = await performQuery<AccountTopPagesQuery>({
                        kind: NodeKind.AccountTopPagesQuery,
                        tags: CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS,
                        accountId: props.accountId,
                        weeks: values.weeks,
                    })
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),
    reducers({
        loadFailed: [
            false,
            {
                loadResult: () => false,
                loadResultSuccess: () => false,
                loadResultFailure: () => true,
            },
        ],
    }),
    selectors({
        config: [
            (s) => [s.weeks, s.productKey],
            (weeks: AccountWidgetWeeks, productKey: string | null): Record<string, string> =>
                productKey ? { weeks: String(weeks), productKey } : { weeks: String(weeks) },
        ],
    }),
    listeners(({ actions, props, values }) => ({
        setWeeks: ({ weeks }) => {
            props.onConfigChange?.(values.config)
            posthog.capture(AccountsEvents.TopPagesWeeksChanged, { weeks })
            actions.loadResult()
        },
        setProductKey: ({ productKey }) => {
            props.onConfigChange?.(values.config)
            posthog.capture(AccountsEvents.TopPagesProductFiltered, { has_filter: productKey !== null })
        },
        loadResultFailure: ({ errorObject }) => {
            posthog.captureException(errorObject, { scope: 'accountTopPagesLogic.loadResult' })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadResult()
    }),
])
