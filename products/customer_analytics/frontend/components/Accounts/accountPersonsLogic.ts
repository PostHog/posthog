/** Marks events from the persons-API path so dashboards can tell it apart from the organization-members path. */
// pinned: analytics property value, renaming breaks dashboards
export const ACCOUNT_PERSONS_READ_SOURCE = 'account_persons'

export interface AccountPersonsLogicProps extends AccountViewTileLogicProps {
    accountId: string
}

/**
 * Loading, error, empty, and filtered-empty are separate screens.
 * `loading` covers "not asked yet" and a retry after a failure, so stale rows never sit under an error.
 */
