export const accountPersonsLogic = kea<accountPersonsLogicType>([
    path((key) => ['scenes', 'customerAnalytics', 'accounts', 'accountPersonsLogic', key]),
    props({} as AccountPersonsLogicProps),
    key((props) => `${props.accountId}:${props.instanceId ?? 'default'}`),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        setPage: (page: number) => ({ page }),
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        setSorting: (sorting: Sorting | null) => ({ sorting }),
        setPropertyFilters: (filters: AnyPropertyFilter[]) => ({ filters }),
        // The filter UI emits half-built rows. This fires only once the set of usable filters changes.
        applyPropertyFilters: true as const,
        addPropertyColumn: (propertyKey: string) => ({ propertyKey }),
        removePropertyColumn: (propertyKey: string) => ({ propertyKey }),
        copyEmails: (emails: string[]) => ({ emails }),
    }),
    loaders(({ props, values }) => ({
        personsResponse: [
            null as AccountPersonsResponseApi | null,
            {
                loadPersons: async (_ = null, breakpoint) => {
                    // The shared loaders plugin reports and toasts failures, so this only has to drop stale responses.
                    const response = await accountsPersonsList(
                        String(values.currentTeamId),
                        props.accountId,
                        values.requestParams
                    )
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers(({ props }) => {
        const initial = parsePersistedPersonsConfig(props.initialConfig)
        return {
            page: [
                1,
                {
                    setPage: (_, { page }) => page,
                    setSearchTerm: () => 1,
                    setSorting: () => 1,
                    applyPropertyFilters: () => 1,
                    removePropertyColumn: () => 1,
                },
            ],
            searchTerm: [initial.searchTerm, { setSearchTerm: (_, { searchTerm }) => searchTerm }],
            // A cleared sort falls back to the API default, which the table then shows as the active sort.
            sorting: [
                initial.sorting as Sorting,
                {
                    setSorting: (_, { sorting }) => sorting ?? DEFAULT_PERSONS_SORTING,
                    removePropertyColumn: (state, { propertyKey }) =>
                        state.columnKey === propertyColumnKey(propertyKey) ? DEFAULT_PERSONS_SORTING : state,
                },
            ],
            propertyColumns: [
                initial.propertyColumns,
                {
                    addPropertyColumn: (state, { propertyKey }) => normalizePropertyColumns([...state, propertyKey]),
                    removePropertyColumn: (state, { propertyKey }) => state.filter((key) => key !== propertyKey),
                },
            ],
            propertyFilters: [
                initial.propertyFilters,
                {
                    setPropertyFilters: (_, { filters }) =>
                        filters.filter(
                            (filter): filter is PersonPropertyFilter => filter.type === PropertyFilterType.Person
                        ),
                },
            ],
            // Not reset by loadPersons: a retry must keep showing "loading", not the previous error or stale rows.
            lastLoadFailed: [
                false,
                {
                    loadPersonsSuccess: () => false,
                    loadPersonsFailure: () => true,
                },
            ],
        }
    }),
    selectors({
        activeFilters: [
            (s) => [s.propertyFilters],
            (filters: PersonPropertyFilter[]) => completePersonPropertyFilters(filters),
        ],
        selectedPropertyKeys: [(s) => [s.propertyColumns], (columns: string[]) => [EMAIL_PROPERTY_KEY, ...columns]],
        hasActiveSearchOrFilters: [
            (s) => [s.searchTerm, s.activeFilters],
            (searchTerm: string, activeFilters: PersonPropertyFilter[]) =>
                searchTerm.trim().length > 0 || activeFilters.length > 0,
        ],
        requestParams: [
            (s) => [s.page, s.searchTerm, s.activeFilters, s.selectedPropertyKeys, s.sorting],
            (
                page: number,
                searchTerm: string,
                activeFilters: PersonPropertyFilter[],
                selectedPropertyKeys: string[],
                sorting: Sorting
            ): AccountsPersonsListParams => {
                const search = searchTerm.trim()
                return {
                    limit: ACCOUNT_PERSONS_PAGE_SIZE,
                    offset: (page - 1) * ACCOUNT_PERSONS_PAGE_SIZE,
                    order_by: sortingToOrderBy(sorting),
                    select: JSON.stringify(selectedPropertyKeys),
                    ...(search ? { search } : {}),
                    ...(activeFilters.length ? { properties: JSON.stringify(activeFilters) } : {}),
                }
            },
        ],
        hasMore: [
            (s) => [s.personsResponse],
            (response: AccountPersonsResponseApi | null): boolean => response?.has_more ?? false,
        ],
        viewState: [
            (s) => [s.personsResponse, s.personsResponseLoading, s.lastLoadFailed, s.hasActiveSearchOrFilters],
            (
                response: AccountPersonsResponseApi | null,
                loading: boolean,
                lastLoadFailed: boolean,
                hasActiveSearchOrFilters: boolean
            ): AccountPersonsViewState => {
                if (lastLoadFailed) {
                    return loading ? 'loading' : 'error'
                }
                if (response === null) {
                    return 'loading'
                }
                if (!response.membership_ready) {
                    return loading ? 'loading' : 'notReady'
                }
                if (response.results.length === 0) {
                    return hasActiveSearchOrFilters ? 'filteredEmpty' : 'empty'
                }
                return 'loaded'
            },
        ],
        persons: [
            (s) => [s.viewState, s.personsResponse],
            (viewState: AccountPersonsViewState, response: AccountPersonsResponseApi | null): AccountPersonApi[] =>
                viewState === 'loaded' ? (response?.results ?? []) : [],
        ],
        config: [
            (s) => [s.searchTerm, s.sorting, s.propertyColumns, s.propertyFilters],
            (
                searchTerm: string,
                sorting: Sorting,
                propertyColumns: string[],
                propertyFilters: PersonPropertyFilter[]
            ): Record<string, unknown> => ({
                searchTerm,
                sorting,
                propertyColumns,
                propertyFilters,
            }),
        ],
    }),
    listeners(({ actions, props, values, selectors }) => ({
        setPage: ({ page }) => {
            actions.loadPersons()
            posthog.capture(AccountsEvents.RelatedUsersPageChanged, {
                page,
                read_source: ACCOUNT_PERSONS_READ_SOURCE,
            })
        },
        setSearchTerm: async ({ searchTerm }, breakpoint) => {
            await breakpoint(300)
            props.onConfigChange?.(values.config)
            actions.loadPersons()
            posthog.capture(AccountsEvents.RelatedUsersSearched, {
                has_query: searchTerm.trim().length > 0,
                query_length: searchTerm.trim().length,
                read_source: ACCOUNT_PERSONS_READ_SOURCE,
            })
        },
        setSorting: ({ sorting }) => {
            props.onConfigChange?.(values.config)
            actions.loadPersons()
            posthog.capture(AccountsEvents.RelatedUsersSorted, {
                column: sortColumnForAnalytics(sorting),
                direction: sorting ? (sorting.order === -1 ? 'desc' : 'asc') : 'cleared',
                read_source: ACCOUNT_PERSONS_READ_SOURCE,
            })
        },
        setPropertyFilters: (_, __, ___, previousState) => {
            const before = JSON.stringify(selectors.activeFilters(previousState))
            if (before !== JSON.stringify(values.activeFilters)) {
                actions.applyPropertyFilters()
            }
        },
        applyPropertyFilters: () => {
            props.onConfigChange?.(values.config)
            actions.loadPersons()
            posthog.capture(AccountsEvents.RelatedUsersPropertyFiltered, {
                filter_count: values.activeFilters.length,
                is_cleared: values.activeFilters.length === 0,
                read_source: ACCOUNT_PERSONS_READ_SOURCE,
            })
        },
        addPropertyColumn: (_, __, ___, previousState) => {
            if (selectors.propertyColumns(previousState).length === values.propertyColumns.length) {
                return
            }
            props.onConfigChange?.(values.config)
            actions.loadPersons()
            posthog.capture(AccountsEvents.RelatedUsersColumnsChanged, {
                change: 'added',
                column_count: values.propertyColumns.length,
                read_source: ACCOUNT_PERSONS_READ_SOURCE,
            })
        },
        removePropertyColumn: () => {
            props.onConfigChange?.(values.config)
            actions.loadPersons()
            posthog.capture(AccountsEvents.RelatedUsersColumnsChanged, {
                change: 'removed',
                column_count: values.propertyColumns.length,
                read_source: ACCOUNT_PERSONS_READ_SOURCE,
            })
        },
        copyEmails: async ({ emails }) => {
            const unique = Array.from(new Set(emails))
            const copied = await copyToClipboard(
                unique.join(', '),
                unique.length === 1 ? 'email address' : 'email addresses'
            )
            if (copied) {
                posthog.capture(AccountsEvents.RelatedUserEmailsCopied, {
                    user_count: unique.length,
                    read_source: ACCOUNT_PERSONS_READ_SOURCE,
                })
            }
        },
    })),
    afterMount(({ actions, props }) => {
        if (props.accountId) {
            actions.loadPersons()
        }
    }),
])
