import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api, { CountedPaginatedResponse } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { SignalReport, SignalReportStatus } from 'scenes/inbox/types'
import { DismissalReasonValue } from 'scenes/inbox/utils/dismissalReasons'
import { userLogic } from 'scenes/userLogic'

import type { UserType } from '../../../../../frontend/src/types'

export const CUSTOMER_ANALYTICS_SCOUT_NAMES = ['signals-scout-customer-analytics', 'signals-scout-product-mix']

// ponytail: single page of 100; add pagination when a team's scout reports outgrow it.
const REPORTS_LIMIT = 100

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reportsLogicValues {
    user: UserType | null // userLogic
    myReportsOnly: boolean
    reports: SignalReport[]
    reportsResponse: CountedPaginatedResponse<SignalReport> | null
    reportsResponseLoading: boolean
    statusFilter: SignalReportStatus | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reportsLogicActions {
    archiveReport: (
        reportId: string,
        reason: DismissalReasonValue,
        note: string
    ) => {
        note: string
        reason:
            | 'already_fixed'
            | 'analysis_wrong'
            | 'other'
            | 'report_unclear'
            | 'wontfix_intentional'
            | 'wontfix_irrelevant'
        reportId: string
    }
    loadReports: (_: any) => any
    loadReportsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadReportsSuccess: (
        reportsResponse: CountedPaginatedResponse<SignalReport>,
        payload?: any
    ) => {
        reportsResponse: CountedPaginatedResponse<SignalReport>
        payload?: any
    }
    setMyReportsOnly: (myReportsOnly: boolean) => {
        myReportsOnly: boolean
    }
    setStatusFilter: (status: SignalReportStatus | null) => {
        status: SignalReportStatus | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reportsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        reports: (reportsResponse: CountedPaginatedResponse<SignalReport> | null) => SignalReport[]
    }
}

export type reportsLogicType = MakeLogicType<
    reportsLogicValues,
    reportsLogicActions,
    Record<string, any>,
    reportsLogicMeta
>

export const reportsLogic = kea<reportsLogicType>([
    path(['products', 'customer_analytics', 'frontend', 'components', 'Reports', 'reportsLogic']),
    connect(() => ({
        values: [userLogic, ['user']],
    })),
    actions({
        setStatusFilter: (status: SignalReportStatus | null) => ({ status }),
        setMyReportsOnly: (myReportsOnly: boolean) => ({ myReportsOnly }),
        archiveReport: (reportId: string, reason: DismissalReasonValue, note: string) => ({ reportId, reason, note }),
    }),
    loaders(({ values }) => ({
        reportsResponse: [
            null as CountedPaginatedResponse<SignalReport> | null,
            {
                loadReports: async (_, breakpoint) => {
                    const response = await api.signalReports.list({
                        scout: CUSTOMER_ANALYTICS_SCOUT_NAMES.join(','),
                        limit: REPORTS_LIMIT,
                        ...(values.statusFilter ? { status: values.statusFilter } : {}),
                        ...(values.myReportsOnly && values.user?.uuid ? { suggested_reviewers: values.user.uuid } : {}),
                    })
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers({
        statusFilter: [null as SignalReportStatus | null, { setStatusFilter: (_, { status }) => status }],
        myReportsOnly: [false, { setMyReportsOnly: (_, { myReportsOnly }) => myReportsOnly }],
    }),
    selectors({
        reports: [
            (s) => [s.reportsResponse],
            (reportsResponse: CountedPaginatedResponse<SignalReport> | null): SignalReport[] =>
                reportsResponse?.results ?? [],
        ],
    }),
    listeners(({ actions }) => ({
        setStatusFilter: () => actions.loadReports(null),
        setMyReportsOnly: () => actions.loadReports(null),
        archiveReport: async ({ reportId, reason, note }) => {
            try {
                await api.signalReports.setState(reportId, {
                    state: 'suppressed',
                    dismissal_reason: reason,
                    ...(note ? { dismissal_note: note } : {}),
                })
            } catch (error: any) {
                lemonToast.error(error?.detail || error?.message || 'Failed to archive report')
            }
            actions.loadReports(null)
        },
    })),
    afterMount(({ actions }) => {
        actions.loadReports(null)
    }),
])
