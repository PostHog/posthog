import { MakeLogicType, afterMount, connect, kea, path } from 'kea'
import { subscriptions } from 'kea-subscriptions'

import { productSetupStatusLogic } from 'lib/components/ProductEmptyState/productSetupStatusLogic'
import type { ProductSetupStatus } from 'lib/components/ProductEmptyState/types'
import { GroupsAccessStatus, groupsAccessLogic } from 'lib/introductions/groupsAccessLogic'
import { teamLogic } from 'scenes/teamLogic'

import { ProductKey } from '~/queries/schema/schema-general'

export function statusFromGroupsAccess(groupsAccessStatus: GroupsAccessStatus): ProductSetupStatus {
    if (groupsAccessStatus === GroupsAccessStatus.AlreadyUsing) {
        return 'has-data'
    }
    if (groupsAccessStatus === GroupsAccessStatus.HasAccess) {
        return 'needs-setup'
    }
    // No access, upgrade needed, or hidden: fail open so the scene's own groups
    // introduction and upgrade messaging take over.
    return 'unknown'
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customerAnalyticsSetupLogicValues {
    groupsAccessStatus: GroupsAccessStatus // groupsAccessLogic
    setupStatus: ProductSetupStatus // productSetupStatusLogic
    currentTeamId: number | null // teamLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customerAnalyticsSetupLogicActions {
    setDetectedStatus: (status: ProductSetupStatus) => {
        status: ProductSetupStatus
    } // productSetupStatusLogic
}

export type customerAnalyticsSetupLogicType = MakeLogicType<
    customerAnalyticsSetupLogicValues,
    customerAnalyticsSetupLogicActions
>

/**
 * Setup detection for the customer analytics empty state. The product is built
 * on group analytics, so "set up" means the project already sends group data
 * (group types exist). The verdict is synchronous, derived from the team.
 */
export const customerAnalyticsSetupLogic = kea<customerAnalyticsSetupLogicType>([
    path(['products', 'customer_analytics', 'frontend', 'emptyState', 'customerAnalyticsSetupLogic']),
    connect(() => ({
        values: [
            groupsAccessLogic,
            ['groupsAccessStatus'],
            teamLogic,
            ['currentTeamId'],
            productSetupStatusLogic({ productKey: ProductKey.CUSTOMER_ANALYTICS }),
            ['status as setupStatus'],
        ],
        actions: [productSetupStatusLogic({ productKey: ProductKey.CUSTOMER_ANALYTICS }), ['setDetectedStatus']],
    })),
    subscriptions(({ actions, values }) => {
        const reportStatus = (): void => actions.setDetectedStatus(statusFromGroupsAccess(values.groupsAccessStatus))
        // The verdict covers the team (and its group types) arriving after mount. The team id
        // covers the rest: a status only counts for the team it was detected for, and the
        // first report can land before the team is known, with the same verdict either side
        // of that. Without this trigger the stamp stays stale, which the gate reads as
        // `loading` for good.
        return { groupsAccessStatus: reportStatus, currentTeamId: reportStatus }
    }),
    afterMount(({ actions, values }) => {
        actions.setDetectedStatus(statusFromGroupsAccess(values.groupsAccessStatus))
    }),
])
