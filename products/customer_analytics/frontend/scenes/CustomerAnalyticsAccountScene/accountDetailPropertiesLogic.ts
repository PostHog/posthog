function customSavingKey(definitionId: string): string {
    return `custom:${definitionId}`
}

function relationshipSavingKey(definitionId: string): string {
    return `relationship:${definitionId}`
}

export const accountDetailPropertiesLogic = kea<accountDetailPropertiesLogicType>([
    props({} as AccountDetailPropertiesLogicProps),
    key((props) => props.accountId),
    path((key) => [
        'products',
        'customer_analytics',
        'frontend',
        'scenes',
        'CustomerAnalyticsAccountScene',
        'accountDetailPropertiesLogic',
        key,
    ]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [membersLogic, ['ensureAllMembersLoaded']],
    })),
    actions({
        setPinnedPropertyKeys: (keys: string[]) => ({ keys }),
        togglePinnedProperty: (key: string) => ({ key }),
        setShowAllProperties: (show: boolean) => ({ show }),
        setEditingPropertyKey: (key: string | null) => ({ key }),
        setConfiguringPins: (open: boolean) => ({ open }),
        saveCustomPropertyValue: (definitionId: string, value: CustomPropertyValue) => ({ definitionId, value }),
        saveCustomPropertyValueDone: (definitionId: string, value: CustomPropertyValue | null) => ({
            definitionId,
            value,
        }),
        assignRelationship: (definitionId: string, user: UserBasicType | null) => ({ definitionId, user }),
        assignRelationshipDone: (definitionId: string, userId: number | null | undefined) => ({
            definitionId,
            userId,
        }),
    }),
    loaders(({ props, values }) => ({
        definitions: [
            null as CustomPropertyDefinitionApi[] | null,
            {
                loadDefinitions: async (): Promise<CustomPropertyDefinitionApi[]> =>
                    (await customPropertyDefinitionsList(String(values.currentTeamId))).results,
            },
        ],
        relationshipDefinitions: [
            null as AccountRelationshipDefinitionApi[] | null,
            {
                loadRelationshipDefinitions: async (): Promise<AccountRelationshipDefinitionApi[]> =>
                    (await accountRelationshipDefinitionsList(String(values.currentTeamId))).results,
            },
        ],
        customValues: [
            null as CustomPropertyValueApi[] | null,
            {
                loadCustomValues: async (): Promise<CustomPropertyValueApi[]> =>
                    await accountsCustomPropertyValuesList(String(values.currentTeamId), props.accountId),
            },
        ],
        relationships: [
            null as AccountRelationshipApi[] | null,
            {
                loadRelationships: async (): Promise<AccountRelationshipApi[]> =>
                    await accountsRelationshipsList(String(values.currentTeamId), props.accountId),
            },
        ],
    })),
    reducers(() => ({
        pinnedPropertyKeys: [
            null as string[] | null,
            {
                persist: true,
                storageKey: `customerAnalytics.accountDetail.accountDetailPropertiesLogic.${getCurrentTeamId()}.pinnedPropertyKeys`,
            },
            {
                setPinnedPropertyKeys: (_, { keys }) => keys,
            },
        ],
        showAllProperties: [
            false,
            {
                setShowAllProperties: (_, { show }) => show,
            },
        ],
        editingPropertyKey: [
            null as string | null,
            {
                setEditingPropertyKey: (_, { key }) => key,
                saveCustomPropertyValue: () => null,
            },
        ],
        configuringPins: [
            false,
            {
                setConfiguringPins: (_, { open }) => open,
            },
        ],
        savingPropertyKeys: [
            {} as Record<string, boolean>,
            {
                saveCustomPropertyValue: (state, { definitionId }) => ({
                    ...state,
                    [customSavingKey(definitionId)]: true,
                }),
                saveCustomPropertyValueDone: (state, { definitionId }) => ({
                    ...state,
                    [customSavingKey(definitionId)]: false,
                }),
                assignRelationship: (state, { definitionId }) => ({
                    ...state,
                    [relationshipSavingKey(definitionId)]: true,
                }),
                assignRelationshipDone: (state, { definitionId }) => ({
                    ...state,
                    [relationshipSavingKey(definitionId)]: false,
                }),
            },
        ],
        valueOverrides: [
            {} as Record<string, CustomPropertyValue>,
            {
                saveCustomPropertyValueDone: (state, { definitionId, value }) => {
                    if (value === null) {
                        const { [definitionId]: _dropped, ...rest } = state
                        return rest
                    }
                    return { ...state, [definitionId]: value }
                },
                loadCustomValuesSuccess: () => ({}),
            },
        ],
        relationshipUserOverrides: [
            {} as Record<string, number | null>,
            {
                assignRelationshipDone: (state, { definitionId, userId }) => {
                    if (userId === undefined) {
                        const { [definitionId]: _dropped, ...rest } = state
                        return rest
                    }
                    return { ...state, [definitionId]: userId }
                },
                loadRelationshipsSuccess: () => ({}),
            },
        ],
        propertiesLoadFailed: [
            false,
            {
                loadDefinitionsFailure: () => true,
                loadRelationshipDefinitionsFailure: () => true,
                loadCustomValuesFailure: () => true,
                loadRelationshipsFailure: () => true,
                loadDefinitions: () => false,
            },
        ],
    })),
    selectors({
        descriptors: [
            (s) => [s.definitions, s.relationshipDefinitions],
            (
                definitions: CustomPropertyDefinitionApi[] | null,
                relationshipDefinitions: AccountRelationshipDefinitionApi[] | null
            ): AccountPropertyDescriptor[] =>
                definitions === null || relationshipDefinitions === null
                    ? EMPTY_DESCRIPTORS
                    : buildAccountPropertyDescriptors(definitions, relationshipDefinitions),
        ],
        pinnedDescriptors: [
            (s) => [s.descriptors, s.pinnedPropertyKeys],
            (
                descriptors: AccountPropertyDescriptor[],
                pinnedPropertyKeys: string[] | null
            ): AccountPropertyDescriptor[] => resolvePinnedProperties(descriptors, pinnedPropertyKeys),
        ],
        propertiesLoading: [
            (s) => [s.definitions, s.relationshipDefinitions, s.customValues, s.relationships, s.propertiesLoadFailed],
            (
                definitions: CustomPropertyDefinitionApi[] | null,
                relationshipDefinitions: AccountRelationshipDefinitionApi[] | null,
                customValues: CustomPropertyValueApi[] | null,
                relationships: AccountRelationshipApi[] | null,
                propertiesLoadFailed: boolean
            ): boolean =>
                !propertiesLoadFailed &&
                (definitions === null ||
                    relationshipDefinitions === null ||
                    customValues === null ||
                    relationships === null),
        ],
        valueByDefinitionId: [
            (s) => [s.customValues, s.valueOverrides],
            (
                customValues: CustomPropertyValueApi[] | null,
                valueOverrides: Record<string, CustomPropertyValue>
            ): Record<string, CustomPropertyValue> => {
                const result: Record<string, CustomPropertyValue> = {}
                for (const value of customValues ?? []) {
                    result[value.definition_id] = value.value
                }
                return { ...result, ...valueOverrides }
            },
        ],
        userIdsByRelationshipDefinitionId: [
            (s) => [s.relationships, s.relationshipUserOverrides],
            (
                relationships: AccountRelationshipApi[] | null,
                relationshipUserOverrides: Record<string, number | null>
            ): Record<string, number[]> => {
                const result: Record<string, number[]> = {}
                for (const relationship of relationships ?? []) {
                    if (relationship.ended_at || !relationship.user) {
                        continue
                    }
                    const definitionId = relationship.definition.id
                    result[definitionId] = [...(result[definitionId] ?? []), relationship.user.id]
                }
                for (const [definitionId, userId] of Object.entries(relationshipUserOverrides)) {
                    result[definitionId] = userId === null ? [] : [userId]
                }
                return result
            },
        ],
        isPropertySaving: [
            (s) => [s.savingPropertyKeys],
            (savingPropertyKeys: Record<string, boolean>) =>
                (key: string): boolean =>
                    !!savingPropertyKeys[key],
        ],
    }),
    listeners(({ actions, props, values }) => ({
        togglePinnedProperty: ({ key }) => {
            const current = values.pinnedDescriptors.map((descriptor) => descriptor.key)
            const next = current.includes(key) ? current.filter((pinned) => pinned !== key) : [...current, key]
            actions.setPinnedPropertyKeys(next)
            posthog.capture(AccountsEvents.DetailPinnedPropertiesChanged, { count: next.length })
        },
        saveCustomPropertyValue: async ({ definitionId, value }) => {
            if (values.isPropertySaving(customSavingKey(definitionId))) {
                return
            }
            try {
                const saved = await accountsCustomPropertyValuesCreate(String(values.currentTeamId), props.accountId, {
                    definition: definitionId,
                    value,
                })
                actions.saveCustomPropertyValueDone(definitionId, saved.value)
                posthog.capture(AccountsEvents.DetailPropertyEdited, { kind: 'custom' })
            } catch (error) {
                actions.saveCustomPropertyValueDone(definitionId, null)
                lemonToast.error("Couldn't save the property. Try again.")
                posthog.captureException(error instanceof Error ? error : new Error('Could not save property'), {
                    scope: 'accountDetailPropertiesLogic.saveCustomPropertyValue',
                })
            }
        },
        assignRelationship: async ({ definitionId, user }) => {
            const projectId = String(values.currentTeamId)
            try {
                if (user) {
                    // Assigning a single-holder relationship ends the current holder server-side.
                    await accountsRelationshipsCreate(projectId, props.accountId, {
                        definition: definitionId,
                        user: user.id,
                    })
                } else {
                    const active = (values.relationships ?? []).filter(
                        (relationship) => relationship.definition.id === definitionId && !relationship.ended_at
                    )
                    await Promise.all(
                        active.map((relationship) =>
                            accountsRelationshipsEndCreate(projectId, props.accountId, relationship.id)
                        )
                    )
                }
                actions.assignRelationshipDone(definitionId, user ? user.id : null)
                posthog.capture(AccountsEvents.DetailPropertyEdited, { kind: 'relationship' })
                actions.loadRelationships()
            } catch (error) {
                actions.assignRelationshipDone(definitionId, undefined)
                lemonToast.error("Couldn't update the assignment. Try again.")
                posthog.captureException(error instanceof Error ? error : new Error('Could not assign relationship'), {
                    scope: 'accountDetailPropertiesLogic.assignRelationship',
                })
            }
        },
        loadDefinitionsFailure: ({ errorObject }) => {
            posthog.captureException(
                errorObject instanceof Error ? errorObject : new Error('Could not load account properties'),
                { scope: 'accountDetailPropertiesLogic.loadDefinitions' }
            )
        },
    })),
    afterMount(({ actions }) => {
        actions.loadDefinitions()
        actions.loadRelationshipDefinitions()
        actions.loadCustomValues()
        actions.loadRelationships()
        // Relationship holders render from the members list, which only loads on request.
        actions.ensureAllMembersLoaded()
    }),
])
