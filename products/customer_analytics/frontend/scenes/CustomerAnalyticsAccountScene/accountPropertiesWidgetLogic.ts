export const accountPropertiesWidgetLogic: LogicWrapper<accountPropertiesWidgetLogicType> =
    kea<accountPropertiesWidgetLogicType>([
        props({} as AccountPropertiesWidgetLogicProps),
        key(({ projectId, accountId, instanceId }) => `${projectId}:${accountId}:${instanceId ?? 'default'}`),
        path((key) => ['products', 'customer_analytics', 'accountPropertiesWidgetLogic', key]),
        connect(({ projectId, accountId }: AccountPropertiesWidgetLogicProps) => ({
            values: [
                accountPropertyDataLogic({ projectId, accountId }),
                ['account', 'accountLoading', 'accountLoadFailed'],
                teamLogic,
                ['currentTeam'],
            ],
            actions: [accountPropertyDataLogic({ projectId, accountId }), ['loadAccount']],
            logic: [accountPropertyUpdatesLogic],
        })),
        actions({
            editNativeProperty: (propertyKey: AccountNativePropertyKey) => ({ propertyKey }),
            cancelNativeEditing: true,
            setNativeDraft: (draft: AccountNativePropertyValue) => ({ draft }),
            saveNativeProperty: true,
            setReferences: (references: AccountWidgetPropertyReference[]) => ({ references }),
        }),
        loaders(({ props }) => ({
            savedAccount: [
                null as AccountApi | null,
                {
                    persistNativeProperty: async ({
                        propertyKey,
                        draft,
                    }: {
                        propertyKey: AccountNativePropertyKey
                        draft: AccountNativePropertyValue
                    }): Promise<AccountApi> =>
                        updateAccountNativeProperties(props.projectId, props.accountId, {
                            [propertyKey]: draft,
                        } as AccountNativePropertyPatch),
                },
            ],
        })),
        reducers(({ props }) => ({
            // Props mutate in place. Redux-backed references keep selectors current when tile configuration changes.
            references: [
                getAccountWidgetProperties(props.initialConfig),
                { setReferences: (_, { references }) => references },
            ],
            nativeEditingKey: [
                null as AccountNativePropertyKey | null,
                {
                    editNativeProperty: (_, { propertyKey }) => propertyKey,
                    cancelNativeEditing: () => null,
                    persistNativePropertySuccess: () => null,
                },
            ],
            nativeDraft: ['' as AccountNativePropertyValue, { setNativeDraft: (_, { draft }) => draft }],
            nativeSaveFailed: [
                false,
                {
                    editNativeProperty: () => false,
                    cancelNativeEditing: () => false,
                    persistNativeProperty: () => false,
                    persistNativePropertySuccess: () => false,
                    persistNativePropertyFailure: () => true,
                },
            ],
        })),
        selectors({
            canEditNativeProperties: [
                () => [],
                (): boolean => userHasAccess(AccessControlResourceType.CustomerAnalytics, AccessControlLevel.Editor),
            ],
            canEditMatching: [
                (s) => [s.currentTeam],
                (team: TeamPublicType | TeamType | null): boolean => canEditEmailMatching(team),
            ],
        }),
        listeners(({ actions, values, props }) => ({
            editNativeProperty: ({ propertyKey }) => {
                posthog.capture(AccountsEvents.AccountPropertyEditorOpened, {
                    source: 'account_view',
                    property_source: 'account',
                })
                actions.setNativeDraft(
                    values.account?.properties?.[propertyKey] ??
                        (propertyKey === 'email_domains' || propertyKey === 'known_emails' ? [] : '')
                )
            },
            saveNativeProperty: () => {
                const propertyKey = values.nativeEditingKey
                if (
                    !propertyKey ||
                    values.savedAccountLoading ||
                    !values.canEditNativeProperties ||
                    !values.account ||
                    !values.references.some(
                        (reference) => reference.kind === 'account' && reference.key === propertyKey
                    ) ||
                    ((propertyKey === 'email_domains' || propertyKey === 'known_emails') && !values.canEditMatching) ||
                    (propertyKey === 'stripe_customer_id' && !values.account.properties?.stripe_customer_id)
                ) {
                    return
                }
                actions.persistNativeProperty({ propertyKey, draft: values.nativeDraft })
            },
            persistNativePropertySuccess: ({ savedAccount }) => {
                accountPropertyUpdatesLogic.actions.accountUpdated(props.projectId, savedAccount)
                dataNodeLogic.findMounted({ key: ACCOUNTS_TABLE_DATA_NODE_KEY })?.actions.loadData('force_async')
                dataNodeLogic.findMounted({ key: ACCOUNTS_METRICS_DATA_NODE_KEY })?.actions.loadData('force_async')
                posthog.capture(AccountsEvents.AccountEdited, { source: 'account_view', name_changed: false })
            },
            persistNativePropertyFailure: () => {
                posthog.capture(AccountsEvents.AccountPropertySaveFailed, {
                    source: 'account_view',
                    property_source: 'account',
                })
            },
        })),
        afterMount(({ actions, values }) => {
            if (!values.account && !values.accountLoading) {
                actions.loadAccount()
            }
        }),
        propsChanged(({ actions, props, values }, previousProps) => {
            if (props.initialConfig !== previousProps.initialConfig) {
                const references = getAccountWidgetProperties(props.initialConfig)
                if (
                    references.length !== values.references.length ||
                    references.some(
                        (reference, index) =>
                            getAccountWidgetPropertyKey(reference) !==
                            getAccountWidgetPropertyKey(values.references[index])
                    )
                ) {
                    actions.setReferences(references)
                }
            }
        }),
    ])
