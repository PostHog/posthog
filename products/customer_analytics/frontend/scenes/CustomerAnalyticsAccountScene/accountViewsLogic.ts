function getAccountViewFailureType(error: unknown): 'conflict' | 'request' {
    return error instanceof ApiError && error.status === 409 ? 'conflict' : 'request'
}

function updateAccountViewComponents(
    projectId: number,
    view: AccountViewApi,
    components: AccountViewComponentInstance[]
): Promise<AccountViewApi> {
    return accountViewsPartialUpdate(String(projectId), view.id, {
        content: createAccountViewContent(components),
        version: view.version,
    })
}

// Every write sends the view's version, so concurrent writes to one view would conflict with each other.
function queueViewWrite(cache: Record<string, any>, viewId: string, write: () => Promise<void>): Promise<void> {
    const writes = (cache.viewWrites ??= new Map<string, Promise<void>>()) as Map<string, Promise<void>>
    const next = (writes.get(viewId) ?? Promise.resolve()).catch(() => undefined).then(write)
    writes.set(viewId, next)
    return next
}

function loadViewsOnceEnabled(logic: Pick<accountViewsLogicType, 'actions' | 'cache' | 'values'>): void {
    if (!logic.cache.viewsRequested && logic.values.featureFlags[FEATURE_FLAGS.CUSTOMER_ANALYTICS_ACCOUNT_VIEWS]) {
        logic.cache.viewsRequested = true
        logic.actions.loadViews()
    }
}

function createAccountViewWithComponentConfig(
    view: AccountViewApi,
    nodeId: string,
    config: AccountViewTileConfig
): AccountViewApi {
    return {
        ...view,
        content: createAccountViewContent(
            parseAccountViewContent(view.content).map((component) =>
                component.nodeId === nodeId ? { ...component, config } : component
            )
        ),
    }
}

