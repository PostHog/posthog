function updateAccountViewComponents(
    projectId: number,
    view: AccountViewApi,
    components: AccountViewComponentInstance[]
): Promise<AccountViewApi> {
    return accountViewsPartialUpdate(String(projectId), view.id, {
        content: createAccountViewContent(components),
        version: view.version,
    })
}

function createAccountViewWithComponentConfig(
    view: AccountViewApi,
    nodeId: string,
    config: AccountViewTileConfig
): AccountViewApi {
    return {
        ...view,
        content: createAccountViewContent(
            parseAccountViewContent(view.content).map((component) =>
                component.nodeId === nodeId ? { ...component, config } : component
            )
        ),
    }
}

