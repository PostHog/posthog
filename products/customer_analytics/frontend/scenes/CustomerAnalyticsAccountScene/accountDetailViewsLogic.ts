function findRow(rows: ColumnConfigurationApi[] | null, id: string): ColumnConfigurationApi | undefined {
    return rows?.find((row) => row.id === id)
}

function reportSaveFailure(scope: string, error: unknown): void {
    lemonToast.error("Couldn't save the view. Try again.")
    posthog.captureException(error instanceof Error ? error : new Error('Could not save account detail view'), {
        scope,
    })
}

export const accountDetailViewsLogic = kea<accountDetailViewsLogicType>([
    path([
        'products',
        'customer_analytics',
        'frontend',
        'scenes',
        'CustomerAnalyticsAccountScene',
        'accountDetailViewsLogic',
    ]),
    connect(() => ({
        values: [userLogic, ['user']],
    })),
    actions({
        setPinnedViewIds: (ids: string[]) => ({ ids }),
        pinView: (id: string) => ({ id }),
        unpinView: (id: string) => ({ id }),
        moveView: (id: string, direction: 'up' | 'down') => ({ id, direction }),
        addWidget: (viewId: string, kind: AccountDetailWidgetKind) => ({ viewId, kind }),
        removeWidget: (viewId: string, kind: AccountDetailWidgetKind) => ({ viewId, kind }),
        setViewText: (viewId: string, text: string) => ({ viewId, text }),
        setConfigureTabsOpen: (open: boolean) => ({ open }),
        setAddViewOpen: (open: boolean) => ({ open }),
        setAddWidgetOpen: (open: boolean) => ({ open }),
    }),
    forms(({ actions }) => ({
        newViewForm: {
            defaults: {
                name: '',
                scope: 'personal',
                widgets: ['summary'],
                pin: true,
            } as NewAccountDetailViewForm,
            errors: ({ name }: NewAccountDetailViewForm) => ({
                name: !name?.trim() ? 'Name is required' : undefined,
            }),
            submit: ({ name, scope, widgets }: NewAccountDetailViewForm) => {
                if (widgets.length === 0) {
                    return
                }
                actions.createView({ input: { name: name.trim(), scope, widgets, text: '' } })
            },
        },
    })),
    loaders(({ values }) => ({
        viewRows: [
            null as ColumnConfigurationApi[] | null,
            {
                loadViews: async (): Promise<ColumnConfigurationApi[]> => {
                    const response = await api.columnConfigurations.list({
                        context_key: ACCOUNT_DETAIL_VIEWS_CONTEXT_KEY,
                    })
                    return response.results
                },
                createView: async ({ input }: { input: AccountDetailViewInput }): Promise<ColumnConfigurationApi[]> => {
                    const row = await api.columnConfigurations.create({ data: serializeAccountDetailView(input) })
                    return [...(values.viewRows ?? []), row]
                },
                updateView: async ({
                    id,
                    updates,
                }: {
                    id: string
                    updates: Partial<AccountDetailViewInput>
                }): Promise<ColumnConfigurationApi[]> => {
                    const current = findRow(values.viewRows, id)
                    if (!current) {
                        return values.viewRows ?? []
                    }
                    const merged = { ...deserializeAccountDetailView(current), ...updates }
                    const row = await api.columnConfigurations.update({ id, data: serializeAccountDetailView(merged) })
                    return (values.viewRows ?? []).map((existing) => (existing.id === id ? row : existing))
                },
                deleteView: async ({ id }: { id: string }): Promise<ColumnConfigurationApi[]> => {
                    await api.columnConfigurations.delete({ id })
                    return (values.viewRows ?? []).filter((existing) => existing.id !== id)
                },
            },
        ],
    })),
    reducers(() => ({
        viewsLoadFailed: [
            false,
            {
                loadViews: () => false,
                loadViewsSuccess: () => false,
                loadViewsFailure: () => true,
            },
        ],
        pinnedViewIds: [
            null as string[] | null,
            {
                persist: true,
                storageKey: `customerAnalytics.accountDetail.accountDetailViewsLogic.${getCurrentTeamId()}.pinnedViewIds`,
            },
            {
                setPinnedViewIds: (_, { ids }) => ids.slice(0, MAX_PINNED_VIEWS),
            },
        ],
        viewSaving: [
            false,
            {
                createView: () => true,
                updateView: () => true,
                deleteView: () => true,
                createViewSuccess: () => false,
                createViewFailure: () => false,
                updateViewSuccess: () => false,
                updateViewFailure: () => false,
                deleteViewSuccess: () => false,
                deleteViewFailure: () => false,
            },
        ],
        configureTabsOpen: [
            false,
            {
                setConfigureTabsOpen: (_, { open }) => open,
            },
        ],
        addViewOpen: [
            false,
            {
                setAddViewOpen: (_, { open }) => open,
                createViewSuccess: () => false,
            },
        ],
        addWidgetOpen: [
            false,
            {
                setAddWidgetOpen: (_, { open }) => open,
                addWidget: () => false,
            },
        ],
    })),
    selectors({
        views: [
            (s) => [s.viewRows],
            (viewRows: ColumnConfigurationApi[] | null): AccountDetailView[] => {
                if (viewRows === null) {
                    return EMPTY_VIEWS
                }
                if (viewRows.length === 0) {
                    return [BUILT_IN_VIEW]
                }
                return viewRows.map(deserializeAccountDetailView)
            },
        ],
        pinnedViews: [
            (s) => [s.views, s.pinnedViewIds],
            (views: AccountDetailView[], pinnedViewIds: string[] | null): AccountDetailView[] =>
                resolvePinnedViews(views, pinnedViewIds),
        ],
        unpinnedViews: [
            (s) => [s.views, s.pinnedViews],
            (views: AccountDetailView[], pinnedViews: AccountDetailView[]): AccountDetailView[] =>
                views.filter((view) => !pinnedViews.includes(view)),
        ],
        myViews: [
            (s) => [s.views, s.user],
            (views: AccountDetailView[], user: UserType | null): AccountDetailView[] =>
                views.filter((view) => view.isBuiltIn || (user !== null && view.createdBy === user.id)),
        ],
        teamViews: [
            (s) => [s.views, s.user],
            (views: AccountDetailView[], user: UserType | null): AccountDetailView[] =>
                views.filter((view) => !view.isBuiltIn && (user === null || view.createdBy !== user.id)),
        ],
        canPinMore: [
            (s) => [s.pinnedViews],
            (pinnedViews: AccountDetailView[]): boolean => pinnedViews.length < MAX_PINNED_VIEWS,
        ],
        canEditView: [
            (s) => [s.user],
            (user: UserType | null) =>
                (view: AccountDetailView): boolean =>
                    canEditAccountDetailView(view, user?.id ?? null),
        ],
    }),
    listeners(({ actions, values }) => ({
        pinView: ({ id }) => {
            const current = values.pinnedViews.map((view) => view.id)
            if (current.includes(id) || current.length >= MAX_PINNED_VIEWS) {
                return
            }
            actions.setPinnedViewIds([...current, id])
        },
        unpinView: ({ id }) => {
            actions.setPinnedViewIds(values.pinnedViews.map((view) => view.id).filter((viewId) => viewId !== id))
        },
        moveView: ({ id, direction }) => {
            const ids = values.pinnedViews.map((view) => view.id)
            const index = ids.indexOf(id)
            const target = direction === 'up' ? index - 1 : index + 1
            if (index === -1 || target < 0 || target >= ids.length) {
                return
            }
            const reordered = [...ids]
            reordered.splice(index, 1)
            reordered.splice(target, 0, id)
            actions.setPinnedViewIds(reordered)
        },
        addWidget: ({ viewId, kind }) => {
            const view = values.views.find((candidate) => candidate.id === viewId)
            if (!view || !values.canEditView(view) || view.widgets.includes(kind)) {
                return
            }
            const widgets = [...view.widgets, kind]
            if (view.isBuiltIn) {
                actions.createView({ input: { name: view.name, scope: 'personal', widgets, text: view.text } })
                return
            }
            actions.updateView({ id: viewId, updates: { widgets } })
        },
        removeWidget: ({ viewId, kind }) => {
            const view = values.views.find((candidate) => candidate.id === viewId)
            if (!view || !values.canEditView(view)) {
                return
            }
            const widgets = view.widgets.filter((widget) => widget !== kind)
            if (widgets.length === 0) {
                lemonToast.info('A view needs at least one widget.')
                return
            }
            if (view.isBuiltIn) {
                actions.createView({ input: { name: view.name, scope: 'personal', widgets, text: view.text } })
                return
            }
            actions.updateView({ id: viewId, updates: { widgets } })
        },
        setViewText: ({ viewId, text }) => {
            const view = values.views.find((candidate) => candidate.id === viewId)
            if (!view || !values.canEditView(view)) {
                return
            }
            if (view.isBuiltIn) {
                actions.createView({ input: { name: view.name, scope: 'personal', widgets: view.widgets, text } })
                return
            }
            actions.updateView({ id: viewId, updates: { text } })
        },
        createViewSuccess: ({ viewRows, payload }) => {
            const created = viewRows?.at(-1)
            if (!created) {
                return
            }
            // The built-in view stops existing once a row is saved, so its pin slot passes to
            // the row that replaced it. A brand-new view takes a free slot when asked to.
            const currentIds = values.pinnedViewIds
            const wasBuiltInPinned = currentIds === null || currentIds.includes(BUILT_IN_VIEW.id)
            const replacesBuiltIn = (viewRows?.length ?? 0) === 1 && wasBuiltInPinned
            const shouldPin = replacesBuiltIn || values.newViewForm.pin
            if (replacesBuiltIn) {
                const base = (currentIds ?? [BUILT_IN_VIEW.id]).map((id) => (id === BUILT_IN_VIEW.id ? created.id : id))
                actions.setPinnedViewIds(base)
            } else if (shouldPin) {
                actions.pinView(created.id)
            }
            actions.resetNewViewForm()
            posthog.capture(AccountsEvents.DetailViewSaved, { scope: payload?.input.scope })
        },
        createViewFailure: ({ errorObject }) => reportSaveFailure('accountDetailViewsLogic.createView', errorObject),
        updateViewSuccess: () => {
            posthog.capture(AccountsEvents.DetailViewUpdated)
        },
        updateViewFailure: ({ errorObject }) => reportSaveFailure('accountDetailViewsLogic.updateView', errorObject),
        deleteViewSuccess: ({ payload }) => {
            if (payload && values.pinnedViewIds?.includes(payload.id)) {
                actions.unpinView(payload.id)
            }
            posthog.capture(AccountsEvents.DetailViewDeleted)
        },
        deleteViewFailure: ({ errorObject }) => {
            lemonToast.error("Couldn't delete the view. Try again.")
            posthog.captureException(
                errorObject instanceof Error ? errorObject : new Error('Could not delete account detail view'),
                { scope: 'accountDetailViewsLogic.deleteView' }
            )
        },
        loadViewsFailure: ({ errorObject }) => {
            posthog.captureException(
                errorObject instanceof Error ? errorObject : new Error('Could not load account detail views'),
                { scope: 'accountDetailViewsLogic.loadViews' }
            )
        },
    })),
    afterMount(({ actions }) => {
        actions.loadViews()
    }),
])
