import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { ApiError } from 'lib/api'
import { Scene } from 'scenes/sceneTypes'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { Breadcrumb } from '~/types'

import { accountsRetrieve } from 'products/customer_analytics/frontend/generated/api'
import type { AccountApi } from 'products/customer_analytics/frontend/generated/api.schemas'

export interface CustomerAnalyticsAccountSceneLogicProps {
    accountId: string
}

function isAccountNotFound(error: unknown): boolean {
    return error instanceof ApiError && error.status === 404
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customerAnalyticsAccountSceneLogicValues {
    currentTeamId: number | null // teamLogic
    account: AccountApi | null
    accountLoadError: unknown
    accountLoading: boolean
    breadcrumbs: Breadcrumb[]
    isAccountMissing: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customerAnalyticsAccountSceneLogicActions {
    loadAccount: () => {
        value: true
    }
    loadAccountFailure: (error: unknown) => {
        error: unknown
    }
    loadAccountSuccess: (account: AccountApi) => {
        account: AccountApi
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customerAnalyticsAccountSceneLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        isAccountMissing: (account: AccountApi | null, accountLoading: boolean, accountLoadError: unknown) => boolean
        breadcrumbs: (account: AccountApi | null) => Breadcrumb[]
    }
}

export type customerAnalyticsAccountSceneLogicType = MakeLogicType<
    customerAnalyticsAccountSceneLogicValues,
    customerAnalyticsAccountSceneLogicActions,
    CustomerAnalyticsAccountSceneLogicProps,
    customerAnalyticsAccountSceneLogicMeta
>

export const customerAnalyticsAccountSceneLogic = kea<customerAnalyticsAccountSceneLogicType>([
    path((key) => [
        'products',
        'customer_analytics',
        'frontend',
        'scenes',
        'CustomerAnalyticsAccountScene',
        'customerAnalyticsAccountSceneLogic',
        key,
    ]),
    props({} as CustomerAnalyticsAccountSceneLogicProps),
    key((props) => props.accountId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        loadAccount: true,
        loadAccountSuccess: (account: AccountApi) => ({ account }),
        loadAccountFailure: (error: unknown) => ({ error }),
    }),
    reducers({
        account: [
            null as AccountApi | null,
            {
                loadAccountSuccess: (_, { account }) => account,
            },
        ],
        accountLoading: [
            false,
            {
                loadAccount: () => true,
                loadAccountSuccess: () => false,
                loadAccountFailure: () => false,
            },
        ],
        accountLoadError: [
            null as unknown,
            {
                loadAccount: () => null,
                loadAccountSuccess: () => null,
                loadAccountFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        isAccountMissing: [
            (s) => [s.account, s.accountLoading, s.accountLoadError],
            (account: AccountApi | null, accountLoading: boolean, accountLoadError: unknown): boolean =>
                !account && !accountLoading && isAccountNotFound(accountLoadError),
        ],
        breadcrumbs: [
            (s) => [s.account],
            (account: AccountApi | null): Breadcrumb[] => [
                {
                    key: Scene.CustomerAnalytics,
                    name: 'Accounts',
                    path: urls.customerAnalyticsAccounts(),
                    iconType: 'cohort',
                },
                {
                    key: Scene.CustomerAnalyticsAccount,
                    name: account?.name ?? 'Account',
                    iconType: 'cohort',
                },
            ],
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadAccount: async () => {
            try {
                actions.loadAccountSuccess(await accountsRetrieve(String(values.currentTeamId), props.accountId))
            } catch (error) {
                actions.loadAccountFailure(error)
            }
        },
        loadAccountFailure: ({ error }) => {
            if (isAccountNotFound(error)) {
                return
            }
            posthog.captureException(error instanceof Error ? error : new Error('Could not load account'), {
                scope: 'customerAnalyticsAccountSceneLogic.loadAccount',
            })
        },
    })),
])
