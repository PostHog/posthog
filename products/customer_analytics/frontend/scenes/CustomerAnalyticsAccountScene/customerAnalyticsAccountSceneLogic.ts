const ACCOUNT_PRESENCE_POLL_INTERVAL_MS = 30_000

export interface CustomerAnalyticsAccountSceneLogicProps {
    accountId?: string
    externalId?: string
    invalidRoute?: boolean
    projectId?: number | null
}

function accountDetailUrl(props: CustomerAnalyticsAccountSceneLogicProps, tab?: string): string {
    return props.externalId
        ? urls.customerAnalyticsAccountByExternalId(props.externalId, tab)
        : urls.customerAnalyticsAccount(props.accountId ?? '', tab)
}

function isAccountNotFound(error: unknown): boolean {
    return error instanceof ApiError && error.status === 404
}

