export const customerAnalyticsAccountSceneLogic = kea<customerAnalyticsAccountSceneLogicType>([
    path((key) => [
        'products',
        'customer_analytics',
        'frontend',
        'scenes',
        'CustomerAnalyticsAccountScene',
        'customerAnalyticsAccountSceneLogic',
        key,
    ]),
    props({} as CustomerAnalyticsAccountSceneLogicProps),
    key((props) => props.accountId),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId', 'customerAnalyticsConfig'],
            accountDetailViewsLogic,
            ['pinnedViews', 'views'],
        ],
        actions: [accountDetailViewsLogic, ['createViewSuccess']],
    })),
    actions({
        loadAccount: true,
        loadAccountSuccess: (account: AccountApi) => ({ account }),
        loadAccountFailure: (error: unknown) => ({ error }),
        selectView: (viewId: string) => ({ viewId }),
        setRequestedViewId: (viewId: string | null) => ({ viewId }),
        updateTags: (tags: string[]) => ({ tags }),
        updateTagsDone: (account: AccountApi | null) => ({ account }),
        openFeatureRequestComposer: true,
    }),
    reducers({
        account: [
            null as AccountApi | null,
            {
                loadAccountSuccess: (_, { account }) => account,
                updateTags: (state, { tags }) => (state ? { ...state, tags } : state),
                updateTagsDone: (state, { account }) => account ?? state,
            },
        ],
        accountLoading: [
            false,
            {
                loadAccount: () => true,
                loadAccountSuccess: () => false,
                loadAccountFailure: () => false,
            },
        ],
        accountLoadError: [
            null as unknown,
            {
                loadAccount: () => null,
                loadAccountSuccess: () => null,
                loadAccountFailure: (_, { error }) => error,
            },
        ],
        // The id the URL asks for. It resolves to a view once the views have loaded, and
        // falls back to the first pinned view when it names nothing the person can see.
        requestedViewId: [
            null as string | null,
            {
                selectView: (_, { viewId }) => viewId,
                setRequestedViewId: (_, { viewId }) => viewId,
            },
        ],
        tagsSaving: [
            false,
            {
                updateTags: () => true,
                updateTagsDone: () => false,
            },
        ],
        featureRequestComposerOpen: [
            false,
            {
                openFeatureRequestComposer: () => true,
            },
        ],
        featureRequestComposerKey: [
            0,
            {
                openFeatureRequestComposer: (state) => state + 1,
            },
        ],
    }),
    selectors({
        isAccountMissing: [
            (s) => [s.account, s.accountLoading, s.accountLoadError],
            (account: AccountApi | null, accountLoading: boolean, accountLoadError: unknown): boolean =>
                !account && !accountLoading && isAccountNotFound(accountLoadError),
        ],
        breadcrumbs: [
            (s) => [s.account],
            (account: AccountApi | null): Breadcrumb[] => [
                {
                    key: Scene.CustomerAnalytics,
                    name: 'Accounts',
                    path: urls.customerAnalyticsAccounts(),
                    iconType: 'cohort',
                },
                {
                    key: Scene.CustomerAnalyticsAccount,
                    name: account?.name ?? 'Account',
                    iconType: 'cohort',
                },
            ],
        ],
        groupTypeIndex: [
            (s) => [s.customerAnalyticsConfig],
            (customerAnalyticsConfig: CustomerAnalyticsConfig): number | null =>
                customerAnalyticsConfig?.account_group_type_index ?? null,
        ],
        selectedView: [
            (s) => [s.requestedViewId, s.pinnedViews, s.views],
            (
                requestedViewId: string | null,
                pinnedViews: AccountDetailView[],
                views: AccountDetailView[]
            ): AccountDetailView | null => {
                const requested = requestedViewId ? views.find((view) => view.id === requestedViewId) : undefined
                return requested ?? pinnedViews[0] ?? views[0] ?? null
            },
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadAccount: async () => {
            try {
                actions.loadAccountSuccess(await accountsRetrieve(String(values.currentTeamId), props.accountId))
            } catch (error) {
                actions.loadAccountFailure(error)
            }
        },
        loadAccountFailure: ({ error }) => {
            if (isAccountNotFound(error)) {
                return
            }
            posthog.captureException(error instanceof Error ? error : new Error('Could not load account'), {
                scope: 'customerAnalyticsAccountSceneLogic.loadAccount',
            })
        },
        selectView: ({ viewId }) => {
            posthog.capture(AccountsEvents.DetailViewSelected, { view_id: viewId })
        },
        createViewSuccess: ({ viewRows }) => {
            // A view saved from this scene is what the person wants to look at next, whether it
            // came from the Add view dialog or from editing the built-in view.
            const created = viewRows?.at(-1)
            if (created) {
                actions.selectView(created.id)
            }
        },
        updateTags: async ({ tags }, breakpoint) => {
            await breakpoint(300)
            try {
                const account = await accountsPartialUpdate(String(values.currentTeamId), props.accountId, { tags })
                actions.updateTagsDone(account)
                tagsModel.findMounted()?.actions.loadTags()
                posthog.capture(AccountsEvents.TagsUpdated, { tag_count: tags.length })
            } catch (error) {
                actions.updateTagsDone(null)
                lemonToast.error("Couldn't save tags. Try again.")
                posthog.captureException(error instanceof Error ? error : new Error('Could not update tags'), {
                    scope: 'customerAnalyticsAccountSceneLogic.updateTags',
                })
                actions.loadAccount()
            }
        },
    })),
    actionToUrl(({ props }) => ({
        selectView: ({ viewId }) => urls.customerAnalyticsAccount(props.accountId, viewId),
    })),
    urlToAction(({ actions, props, values }) => ({
        [urls.customerAnalyticsAccount(':accountId', ':tab')]: ({ accountId, tab }) => {
            if (accountId !== props.accountId) {
                return
            }
            const requested = tab ?? null
            if (requested !== values.requestedViewId) {
                actions.setRequestedViewId(requested)
            }
        },
        [urls.customerAnalyticsAccount(':accountId')]: ({ accountId }) => {
            if (accountId === props.accountId && values.requestedViewId !== null) {
                actions.setRequestedViewId(null)
            }
        },
    })),
])
