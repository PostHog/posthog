export const customerAnalyticsAccountSceneLogic = kea<customerAnalyticsAccountSceneLogicType>([
    path((key) => [
        'products',
        'customer_analytics',
        'frontend',
        'scenes',
        'CustomerAnalyticsAccountScene',
        'customerAnalyticsAccountSceneLogic',
        key,
    ]),
    props({} as CustomerAnalyticsAccountSceneLogicProps),
    key(
        (props) =>
            `${props.projectId ?? 'unknown'}:${props.externalId ? 'external' : 'id'}:${props.externalId ?? props.accountId ?? 'invalid'}`
    ),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
        actions: [featureFlagLogic, ['setFeatureFlags']],
    })),
    actions({
        loadAccount: true,
        loadAccountSuccess: (account: AccountApi) => ({ account }),
        loadAccountFailure: (error: unknown) => ({ error }),
        loadAccountPresence: (accountId: string) => ({ accountId }),
        loadAccountPresenceSuccess: (viewers: AccountPresenceViewerApi[]) => ({ viewers }),
        startAccountPresencePolling: (accountId: string) => ({ accountId }),
        loadAccountPresenceFailure: (error: unknown) => ({ error }),
        setActiveTab: (tab: AccountExpansionTab) => ({ tab }),
        restoreActiveTab: (tab: string | undefined) => ({ tab: tab ?? DEFAULT_ACCOUNT_TAB }),
        updateTags: (tags: string[]) => ({ tags }),
        updateTagsDone: (account: AccountApi | null) => ({ account }),
    }),
    reducers({
        account: [
            null as AccountApi | null,
            {
                loadAccountSuccess: (_, { account }) => account,
                updateTags: (state, { tags }) => (state ? { ...state, tags } : state),
                updateTagsDone: (state, { account }) => account ?? state,
            },
        ],
        accountLoading: [
            false,
            {
                loadAccount: () => true,
                loadAccountSuccess: () => false,
                loadAccountFailure: () => false,
            },
        ],
        accountLoadError: [
            null as unknown,
            {
                loadAccount: () => null,
                loadAccountSuccess: () => null,
                loadAccountFailure: (_, { error }) => error,
            },
        ],
        accountPresenceViewers: [
            [] as AccountPresenceViewerApi[],
            {
                loadAccountPresenceSuccess: (_, { viewers }) => viewers,
                loadAccountPresenceFailure: () => [],
            },
        ],
        accountPresenceError: [
            null as unknown,
            {
                loadAccountPresence: () => null,
                loadAccountPresenceSuccess: () => null,
                loadAccountPresenceFailure: (_, { error }) => error,
            },
        ],
        requestedTab: [
            DEFAULT_ACCOUNT_TAB as string,
            {
                setActiveTab: (_, { tab }) => tab,
                restoreActiveTab: (_, { tab }) => tab,
            },
        ],
        tagsSaving: [
            false,
            {
                updateTags: () => true,
                updateTagsDone: () => false,
            },
        ],
    }),
    selectors({
        activeTab: [
            (s) => [s.requestedTab, s.featureFlags],
            (requestedTab: string, featureFlags: FeatureFlagsSet): AccountExpansionTab =>
                getVisibleAccountExpansionTab(requestedTab, featureFlags),
        ],
        isAccountMissing: [
            (s, _) => [s.account, s.accountLoading, s.accountLoadError, (_, props) => props.invalidRoute === true],
            (
                account: AccountApi | null,
                accountLoading: boolean,
                accountLoadError: unknown,
                invalidRoute: boolean
            ): boolean => invalidRoute || (!account && !accountLoading && isAccountNotFound(accountLoadError)),
        ],
        breadcrumbs: [
            (s) => [s.account],
            (account: AccountApi | null): Breadcrumb[] => [
                {
                    key: Scene.CustomerAnalytics,
                    name: 'Accounts',
                    path: urls.customerAnalyticsAccounts(),
                    iconType: 'cohort',
                },
                {
                    key: Scene.CustomerAnalyticsAccount,
                    name: account?.name ?? 'Account',
                    iconType: 'cohort',
                },
            ],
        ],
    }),
    listeners(({ actions, cache, props, values }) => ({
        setFeatureFlags: (_, __, ___, previousState) => {
            const previousFeatureFlags = featureFlagLogic.selectors.featureFlags(previousState)
            if (
                props.externalId &&
                !previousFeatureFlags[FEATURE_FLAGS.CUSTOMER_ANALYTICS_CSP] &&
                values.featureFlags[FEATURE_FLAGS.CUSTOMER_ANALYTICS_CSP] &&
                !values.account &&
                !values.accountLoading
            ) {
                actions.loadAccount()
            }
        },
        loadAccount: async (_, breakpoint) => {
            try {
                const projectId = props.projectId
                const identifier = props.externalId ?? props.accountId
                if (!projectId || props.invalidRoute || !identifier) {
                    actions.loadAccountFailure(null)
                    return
                }
                const account = props.externalId
                    ? await accountsByExternalIdRetrieve(String(projectId), { external_id: identifier })
                    : await accountsRetrieve(String(projectId), identifier)
                await breakpoint()
                actions.loadAccountSuccess(account)
            } catch (error) {
                if (error instanceof Error && isBreakpoint(error)) {
                    throw error
                }
                await breakpoint()
                actions.loadAccountFailure(error)
            }
        },
        loadAccountSuccess: ({ account }) => {
            if (!props.externalId) {
                return
            }
            if (!values.featureFlags[FEATURE_FLAGS.CUSTOMER_ANALYTICS_ACCOUNT_SCENE]) {
                const externalRoute = parseExternalAccountPath(router.values.location.pathname)
                router.actions.replace(
                    urls.customerAnalyticsAccount(account.id, externalRoute?.tab),
                    router.values.currentLocation.searchParams,
                    router.values.currentLocation.hashParams
                )
                return
            }
            actions.startAccountPresencePolling(account.id)
        },
        loadAccountFailure: ({ error }) => {
            if (error === null || isAccountNotFound(error)) {
                return
            }
            posthog.captureException(error instanceof Error ? error : new Error('Could not load account'), {
                scope: 'customerAnalyticsAccountSceneLogic.loadAccount',
            })
        },
        startAccountPresencePolling: ({ accountId }) => {
            cache.disposables.add(() => {
                actions.loadAccountPresence(accountId)
                const intervalId = window.setInterval(
                    () => actions.loadAccountPresence(accountId),
                    ACCOUNT_PRESENCE_POLL_INTERVAL_MS
                )
                return () => window.clearInterval(intervalId)
            }, 'accountPresencePolling')
        },
        loadAccountPresence: async ({ accountId }) => {
            cache.accountPresenceRequestSequence = (cache.accountPresenceRequestSequence ?? 0) + 1
            const requestSequence = cache.accountPresenceRequestSequence
            try {
                if (!props.projectId) {
                    return
                }
                const viewers = await accountsPresenceCreate(String(props.projectId), accountId)
                if (requestSequence === cache.accountPresenceRequestSequence) {
                    actions.loadAccountPresenceSuccess(viewers)
                }
            } catch (error) {
                if (requestSequence === cache.accountPresenceRequestSequence) {
                    actions.loadAccountPresenceFailure(error)
                }
            }
        },
        setActiveTab: ({ tab }) => {
            posthog.capture(AccountsEvents.TabViewed, { tab })
        },
        updateTags: async ({ tags }, breakpoint) => {
            const accountId = values.account?.id
            const projectId = props.projectId
            if (!accountId || !projectId) {
                actions.updateTagsDone(null)
                return
            }
            try {
                await breakpoint(300)
                const account = await accountsPartialUpdate(String(projectId), accountId, { tags })
                await breakpoint()
                actions.updateTagsDone(account)
                tagsModel.findMounted()?.actions.loadTags()
                posthog.capture(AccountsEvents.TagsUpdated, { tag_count: tags.length })
            } catch (error) {
                if (error instanceof Error && isBreakpoint(error)) {
                    throw error
                }
                await breakpoint()
                actions.updateTagsDone(null)
                lemonToast.error("Couldn't save tags. Try again.")
                posthog.captureException(error instanceof Error ? error : new Error('Could not update tags'), {
                    scope: 'customerAnalyticsAccountSceneLogic.updateTags',
                })
                actions.loadAccount()
            }
        },
    })),
    actionToUrl(({ props }) => ({
        setActiveTab: ({ tab }) => [
            accountDetailUrl(props, tab === DEFAULT_ACCOUNT_TAB ? undefined : tab),
            router.values.currentLocation.searchParams,
            router.values.currentLocation.hashParams,
        ],
    })),
    urlToAction(({ actions, props }) => {
        if (props.externalId) {
            return {
                [EXTERNAL_ACCOUNT_ROUTE_PATTERN]: () => {
                    actions.restoreActiveTab(parseExternalAccountPath(router.values.location.pathname)?.tab)
                },
            }
        }
        return {
            [`${accountDetailUrl(props)}/:tab`]: ({ tab }) => {
                actions.restoreActiveTab(tab)
            },
            [accountDetailUrl(props)]: () => {
                actions.restoreActiveTab(DEFAULT_ACCOUNT_TAB)
            },
        }
    }),
    afterMount(({ actions, props, values }) => {
        if (props.externalId && !values.featureFlags[FEATURE_FLAGS.CUSTOMER_ANALYTICS_CSP]) {
            return
        }
        actions.loadAccount()
        if (props.accountId) {
            actions.startAccountPresencePolling(props.accountId)
        }
    }),
])
