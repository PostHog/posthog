import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'

import { getTileStringArray, type AccountViewTileLogicProps } from '../../components/Accounts/accountViewTileConfig'
import { accountSidebarPropertiesLogic } from './accountSidebarPropertiesLogic'
import { ACCOUNT_ID_FIELDS, ACCOUNT_LIST_FIELDS, type AccountFieldKey } from './customerAnalyticsAccountSceneLogic'

export const PROPERTIES_CONFIG_KEY = 'properties'
const FIELD_KEY_PREFIX = 'field:'

export const ACCOUNT_FIELDS: readonly { key: AccountFieldKey; label: string; placeholder: string }[] = [
    ...ACCOUNT_ID_FIELDS,
    ...ACCOUNT_LIST_FIELDS,
]

export function accountFieldToPropertyKey(field: AccountFieldKey): string {
    return `${FIELD_KEY_PREFIX}${field}`
}

export function propertyKeyToAccountField(propertyKey: string): AccountFieldKey | null {
    if (!propertyKey.startsWith(FIELD_KEY_PREFIX)) {
        return null
    }
    const field = propertyKey.slice(FIELD_KEY_PREFIX.length)
    return ACCOUNT_FIELDS.find(({ key }) => key === field)?.key ?? null
}

export interface AccountPropertiesTileLogicProps extends AccountViewTileLogicProps {
    accountId: string
    projectId: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountPropertiesTileLogicValues {
    configuratorOpen: boolean
    draftPropertyKeys: string[]
    propertyKeys: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accountPropertiesTileLogicActions {
    closeConfigurator: () => {
        value: true
    }
    openConfigurator: () => {
        value: true
    }
    requestAllPropertyData: () => {
        value: true
    } // accountSidebarPropertiesLogic
    savePropertyKeys: (propertyKeys: string[]) => {
        propertyKeys: string[]
    }
    setDraftPropertyKeys: (propertyKeys: string[]) => {
        propertyKeys: string[]
    }
}

export type accountPropertiesTileLogicType = MakeLogicType<
    accountPropertiesTileLogicValues,
    accountPropertiesTileLogicActions,
    AccountPropertiesTileLogicProps
>

export const accountPropertiesTileLogic = kea<accountPropertiesTileLogicType>([
    path((key) => [
        'products',
        'customer_analytics',
        'frontend',
        'scenes',
        'CustomerAnalyticsAccountScene',
        'accountPropertiesTileLogic',
        key,
    ]),
    props({} as AccountPropertiesTileLogicProps),
    key((props) => `${props.projectId}:${props.accountId}:${props.instanceId ?? 'default'}`),
    connect(({ accountId, projectId }: AccountPropertiesTileLogicProps) => ({
        actions: [accountSidebarPropertiesLogic({ accountId, projectId }), ['requestAllPropertyData']],
    })),
    actions({
        openConfigurator: true,
        closeConfigurator: true,
        setDraftPropertyKeys: (propertyKeys: string[]) => ({ propertyKeys }),
        savePropertyKeys: (propertyKeys: string[]) => ({ propertyKeys }),
    }),
    reducers(({ props }) => ({
        propertyKeys: [
            getTileStringArray(props.initialConfig, PROPERTIES_CONFIG_KEY),
            { savePropertyKeys: (_, { propertyKeys }) => propertyKeys },
        ],
        draftPropertyKeys: [[] as string[], { setDraftPropertyKeys: (_, { propertyKeys }) => propertyKeys }],
        configuratorOpen: [false, { openConfigurator: () => true, closeConfigurator: () => false }],
    })),
    listeners(({ actions, props, values }) => ({
        openConfigurator: () => {
            actions.setDraftPropertyKeys(values.propertyKeys)
        },
        savePropertyKeys: ({ propertyKeys }) => {
            actions.closeConfigurator()
            props.onConfigChange?.({ ...props.initialConfig, [PROPERTIES_CONFIG_KEY]: propertyKeys })
        },
    })),
    afterMount(({ actions }) => {
        actions.requestAllPropertyData()
    }),
])
