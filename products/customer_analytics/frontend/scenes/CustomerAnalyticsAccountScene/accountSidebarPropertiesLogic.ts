export const accountSidebarPropertiesLogic: LogicWrapper<accountSidebarPropertiesLogicType> =
    kea<accountSidebarPropertiesLogicType>([
        props({} as AccountSidebarPropertiesLogicProps),
        key(({ projectId, accountId }) => `${projectId}:${accountId}`),
        path((key) => ['products', 'customer_analytics', 'accountSidebarPropertiesLogic', key]),
        connect(({ projectId }: AccountSidebarPropertiesLogicProps) => ({
            values: [
                accountSidebarConfigLogic({ projectId }),
                [
                    'availableDefinitions',
                    'availableDefinitionsLoadFailed',
                    'config',
                    'configLoadFailed',
                    'resolvedPinnedProperties',
                ],
                membersLogic,
                ['members', 'membersLoading'],
            ],
            actions: [membersLogic, ['ensureAllMembersLoaded']],
        })),
        actions({
            editProperty: (property: AccountSidebarProperty) => ({ property }),
            cancelEditing: true,
            saveCustomProperty: (propertyKey: string, value: AccountCustomPropertyValue) => ({ propertyKey, value }),
            saveRelationship: (propertyKey: string, memberIds: number[]) => ({ propertyKey, memberIds }),
        }),
        loaders(({ props, values }) => ({
            propertyData: [
                null as AccountSidebarPropertyData | null,
                {
                    loadPropertyData: async (_: void, breakpoint): Promise<AccountSidebarPropertyData | null> => {
                        if (values.resolvedPinnedProperties.length === 0) {
                            return null
                        }
                        const [customValues, relationships] = await Promise.all([
                            api.accountsCustomPropertyValuesList(String(props.projectId), props.accountId),
                            api.accountsRelationshipsList(String(props.projectId), props.accountId),
                        ])
                        breakpoint()
                        return { customValues, relationships }
                    },
                },
            ],
            savedPropertyKey: [
                null as string | null,
                {
                    persistCustomProperty: async ({
                        propertyKey,
                        definitionId,
                        value,
                    }: {
                        propertyKey: string
                        definitionId: string
                        value: AccountCustomPropertyValue
                    }): Promise<string> => {
                        await api.accountsCustomPropertyValuesCreate(String(props.projectId), props.accountId, {
                            definition: definitionId,
                            value,
                        })
                        return propertyKey
                    },
                    persistRelationship: async ({
                        propertyKey,
                        definitionId,
                        memberIds,
                        singleHolder,
                    }: {
                        propertyKey: string
                        definitionId: string
                        memberIds: number[]
                        singleHolder: boolean
                    }): Promise<string> => {
                        const projectId = String(props.projectId)
                        const current = await api.accountsRelationshipsList(projectId, props.accountId)
                        const assignments = current.filter(
                            (relationship) => relationship.definition.id === definitionId && !relationship.ended_at
                        )
                        const additions = memberIds.filter(
                            (id) => !assignments.some((relationship) => relationship.user?.id === id)
                        )
                        for (const user of additions) {
                            await api.accountsRelationshipsCreate(projectId, props.accountId, {
                                definition: definitionId,
                                user,
                            })
                        }
                        if (!singleHolder || additions.length === 0) {
                            for (const relationship of assignments) {
                                if (!relationship.user || !memberIds.includes(relationship.user.id)) {
                                    await api.accountsRelationshipsEndCreate(
                                        projectId,
                                        props.accountId,
                                        relationship.id
                                    )
                                }
                            }
                        }
                        return propertyKey
                    },
                },
            ],
        })),
        reducers({
            editingPropertyKey: [
                null as string | null,
                {
                    editProperty: (state, { property }) =>
                        property.editable !== false &&
                        (property.kind === 'relationship' || isCustomPropertyEditable(property.provenance))
                            ? property.key
                            : state,
                    cancelEditing: () => null,
                    persistCustomPropertySuccess: () => null,
                    persistRelationshipSuccess: () => null,
                },
            ],
            savingPropertyKey: [
                null as string | null,
                {
                    persistCustomProperty: (_, { propertyKey }) => propertyKey,
                    persistRelationship: (_, { propertyKey }) => propertyKey,
                    persistCustomPropertySuccess: () => null,
                    persistRelationshipSuccess: () => null,
                    persistCustomPropertyFailure: () => null,
                    persistRelationshipFailure: () => null,
                },
            ],
            propertyDataLoadFailed: [
                false,
                {
                    loadPropertyData: () => false,
                    loadPropertyDataSuccess: () => false,
                    loadPropertyDataFailure: () => true,
                },
            ],
            propertySaveFailed: [
                false,
                {
                    editProperty: () => false,
                    cancelEditing: () => false,
                    persistCustomProperty: () => false,
                    persistRelationship: () => false,
                    persistCustomPropertyFailure: () => true,
                    persistRelationshipFailure: () => true,
                },
            ],
        }),
        selectors({
            sidebarProperties: [
                (s) => [s.resolvedPinnedProperties, s.propertyData],
                (
                    pinned: ResolvedPinnedAccountProperty[],
                    data: AccountSidebarPropertyData | null
                ): AccountSidebarProperty[] =>
                    buildAccountSidebarProperties(
                        pinned,
                        data,
                        userHasAccess(AccessControlResourceType.CustomerAnalytics, AccessControlLevel.Editor)
                    ),
            ],
            availableMembers: [
                (s) => [s.members, s.propertyData],
                (
                    members: OrganizationMemberType[] | null,
                    data: AccountSidebarPropertyData | null
                ): AccountRelationshipMember[] => {
                    const byId = new Map<number, AccountRelationshipMember>()
                    for (const relationship of data?.relationships ?? []) {
                        if (relationship.user) {
                            byId.set(relationship.user.id, relationship.user)
                        }
                    }
                    for (const member of members ?? []) {
                        byId.set(member.user.id, {
                            id: member.user.id,
                            email: member.user.email,
                            name: member.user.first_name,
                        })
                    }
                    return [...byId.values()]
                },
            ],
            propertiesAvailable: [
                (s) => [s.config, s.availableDefinitions, s.resolvedPinnedProperties, s.propertyData],
                (
                    config: UserCustomerAnalyticsConfigApi | null,
                    definitions: AvailableDefinitions | null,
                    pinned: ResolvedPinnedAccountProperty[],
                    data: AccountSidebarPropertyData | null
                ): boolean => config !== null && definitions !== null && (pinned.length === 0 || data !== null),
            ],
            propertiesLoadFailed: [
                (s) => [
                    s.configLoadFailed,
                    s.availableDefinitionsLoadFailed,
                    s.resolvedPinnedProperties,
                    s.propertyDataLoadFailed,
                ],
                (
                    configFailed: boolean,
                    definitionsFailed: boolean,
                    pinned: ResolvedPinnedAccountProperty[],
                    dataFailed: boolean
                ): boolean => configFailed || definitionsFailed || (pinned.length > 0 && dataFailed),
            ],
            // A failed load keeps the values of the previous successful load, so the blocking error
            // state is only for a panel that has nothing to show.
            propertiesPanelState: [
                (s) => [s.propertiesAvailable, s.propertiesLoadFailed],
                (available: boolean, failed: boolean): AccountPropertiesPanelState =>
                    available ? 'ready' : failed ? 'failed' : 'loading',
            ],
            propertiesRefreshFailed: [
                (s) => [s.propertiesAvailable, s.propertiesLoadFailed],
                (available: boolean, failed: boolean): boolean => available && failed,
            ],
        }),
        listeners(({ actions, props, values }) => {
            const refresh = (): void => {
                actions.loadPropertyData()
                accountRelationshipsLogic.findMounted({ accountId: props.accountId })?.actions.loadRelationships()
                dataNodeLogic.findMounted({ key: ACCOUNTS_TABLE_DATA_NODE_KEY })?.actions.loadData('force_async')
                dataNodeLogic.findMounted({ key: ACCOUNTS_METRICS_DATA_NODE_KEY })?.actions.loadData('force_async')
            }
            return {
                editProperty: ({ property }) => {
                    if (property.kind === 'relationship') {
                        actions.ensureAllMembersLoaded()
                    }
                },
                saveCustomProperty: ({ propertyKey, value }) => {
                    const property = values.sidebarProperties.find((row) => row.key === propertyKey)
                    if (
                        values.savingPropertyKey ||
                        property?.kind !== 'custom' ||
                        property.editable === false ||
                        !isCustomPropertyEditable(property.provenance)
                    ) {
                        return
                    }
                    actions.persistCustomProperty({ propertyKey, definitionId: property.definition.id, value })
                },
                saveRelationship: ({ propertyKey, memberIds }) => {
                    const property = values.sidebarProperties.find((row) => row.key === propertyKey)
                    if (values.savingPropertyKey || property?.kind !== 'relationship' || property.editable === false) {
                        return
                    }
                    const selected = [...new Set(memberIds)]
                    if (property.definition.is_single_holder !== false && selected.length > 1) {
                        return
                    }
                    actions.persistRelationship({
                        propertyKey,
                        definitionId: property.definition.id,
                        memberIds: selected,
                        singleHolder: property.definition.is_single_holder !== false,
                    })
                },
                persistCustomPropertySuccess: ({ savedPropertyKey }) => {
                    const property = values.sidebarProperties.find((row) => row.key === savedPropertyKey)
                    if (property?.kind === 'custom') {
                        // The property name and value stay out because they can hold customer data.
                        posthog.capture(AccountsEvents.CustomPropertyUpdated, {
                            display_type: property.definition.display_type,
                            workflow_reference: property.definition.has_workflow_reference,
                        })
                    }
                    refresh()
                },
                persistRelationshipSuccess: ({ savedPropertyKey, payload }) => {
                    const property = values.sidebarProperties.find((row) => row.key === savedPropertyKey)
                    if (property?.kind === 'relationship') {
                        const memberIds = payload?.memberIds ?? []
                        posthog.capture(AccountsEvents.RoleAssigned, {
                            role: ROLE_KEY_BY_NAME[property.definition.name] ?? property.definition.name,
                            is_assigned: memberIds.length > 0,
                            assigned_user_id: memberIds.length === 1 ? memberIds[0] : null,
                            source: 'account_sidebar',
                        })
                    }
                    refresh()
                },
                persistRelationshipFailure: refresh,
                [accountSidebarConfigLogic({ projectId: props.projectId }).actionTypes.loadConfigSuccess]: () =>
                    actions.loadPropertyData(),
                [accountSidebarConfigLogic({ projectId: props.projectId }).actionTypes.persistPinnedPropertiesSuccess]:
                    () => actions.loadPropertyData(),
                [accountSidebarConfigLogic({ projectId: props.projectId }).actionTypes.loadAvailableDefinitionsSuccess]:
                    () => actions.loadPropertyData(),
            }
        }),
        afterMount(({ actions }) => actions.loadPropertyData()),
    ])
