export const accountSidebarPropertiesLogic: LogicWrapper<accountSidebarPropertiesLogicType> =
    kea<accountSidebarPropertiesLogicType>([
        props({} as AccountSidebarPropertiesLogicProps),
        key(({ projectId, accountId, instanceId }) => `${projectId}:${accountId}${instanceId ? `:${instanceId}` : ''}`),
        path((key) => ['products', 'customer_analytics', 'accountSidebarPropertiesLogic', key]),
        connect(({ projectId, accountId }: AccountSidebarPropertiesLogicProps) => ({
            values: [
                accountSidebarConfigLogic({ projectId }),
                [
                    'availableDefinitions',
                    'availableDefinitionsLoadFailed',
                    'config',
                    'configLoadFailed',
                    'resolvedPinnedProperties as sidebarPinnedProperties',
                ],
                accountPropertyDataLogic({ projectId, accountId }),
                ['propertyData', 'propertyDataLoading', 'propertyDataLoadFailed as sharedPropertyDataLoadFailed'],
                membersLogic,
                ['members', 'membersLoading'],
            ],
            actions: [
                membersLogic,
                ['ensureAllMembersLoaded'],
                accountPropertyDataLogic({ projectId, accountId }),
                ['loadPropertyData as reloadPropertyData', 'loadPropertyDataSuccess', 'loadPropertyDataFailure'],
            ],
        })),
        actions({
            loadPropertyData: true,
            setConfiguredPropertyReferences: (references: PinnedAccountProperty[] | null) => ({ references }),
            editProperty: (property: AccountSidebarProperty) => ({ property }),
            cancelEditing: true,
            saveCustomProperty: (
                propertyKey: string,
                value: AccountCustomPropertyValue,
                source: AccountPropertyEditSource = 'account_sidebar'
            ) => ({ propertyKey, value, source }),
            saveRelationship: (
                propertyKey: string,
                memberIds: number[],
                source: AccountPropertyEditSource = 'account_sidebar'
            ) => ({ propertyKey, memberIds, source }),
            setRelationshipEditBaseline: (baseline: RelationshipEditBaseline) => ({ baseline }),
            recordRelationshipRemoval: (propertyKey: string, memberId: number, assignmentId: string) => ({
                propertyKey,
                memberId,
                assignmentId,
            }),
            recordRelationshipAddition: (propertyKey: string, memberId: number, assignmentId: string) => ({
                propertyKey,
                memberId,
                assignmentId,
            }),
        }),
        loaders(({ props, actions }) => ({
            savedPropertyKey: [
                null as string | null,
                {
                    persistCustomProperty: async ({
                        propertyKey,
                        definitionId,
                        value,
                    }: {
                        propertyKey: string
                        definitionId: string
                        value: AccountCustomPropertyValue
                        source: AccountPropertyEditSource
                    }): Promise<string> => {
                        await api.accountsCustomPropertyValuesCreate(String(props.projectId), props.accountId, {
                            definition: definitionId,
                            value,
                        })
                        return propertyKey
                    },
                    persistRelationship: async ({
                        propertyKey,
                        definitionId,
                        memberIds,
                        singleHolder,
                        baseline,
                    }: {
                        propertyKey: string
                        definitionId: string
                        memberIds: number[]
                        singleHolder: boolean
                        baseline: RelationshipEditBaseline
                        source: AccountPropertyEditSource
                    }): Promise<string> => {
                        const projectId = String(props.projectId)
                        const current = await api.accountsRelationshipsList(projectId, props.accountId)
                        const assignments = current.filter(
                            (relationship) => relationship.definition.id === definitionId && !relationship.ended_at
                        )
                        const additions = memberIds.filter(
                            (id) =>
                                !baseline.memberIds.includes(id) &&
                                !assignments.some((relationship) => relationship.user?.id === id)
                        )
                        for (const user of additions) {
                            const created = await api.accountsRelationshipsCreate(projectId, props.accountId, {
                                definition: definitionId,
                                user,
                            })
                            actions.recordRelationshipAddition(propertyKey, user, created.id)
                        }
                        if (!singleHolder || additions.length === 0) {
                            for (const relationship of assignments) {
                                if (
                                    baseline.assignmentIds.includes(relationship.id) &&
                                    relationship.user &&
                                    !memberIds.includes(relationship.user.id)
                                ) {
                                    await api.accountsRelationshipsEndCreate(
                                        projectId,
                                        props.accountId,
                                        relationship.id
                                    )
                                    actions.recordRelationshipRemoval(
                                        propertyKey,
                                        relationship.user.id,
                                        relationship.id
                                    )
                                }
                            }
                        }
                        return propertyKey
                    },
                },
            ],
        })),
        reducers(({ props }) => ({
            // Props mutate in place. Redux-backed references keep selectors current when tile configuration changes.
            configuredPropertyReferences: [
                props.propertyReferences ?? (null as PinnedAccountProperty[] | null),
                { setConfiguredPropertyReferences: (_, { references }) => references },
            ],
            relationshipEditBaseline: [
                null as RelationshipEditBaseline | null,
                {
                    setRelationshipEditBaseline: (_, { baseline }) => baseline,
                    recordRelationshipRemoval: (baseline, { propertyKey, memberId, assignmentId }) =>
                        baseline?.propertyKey === propertyKey
                            ? {
                                  ...baseline,
                                  memberIds: baseline.memberIds.filter((id) => id !== memberId),
                                  assignmentIds: baseline.assignmentIds.filter((id) => id !== assignmentId),
                              }
                            : baseline,
                    recordRelationshipAddition: (baseline, { propertyKey, memberId, assignmentId }) =>
                        baseline?.propertyKey === propertyKey
                            ? {
                                  ...baseline,
                                  memberIds: [...new Set([...baseline.memberIds, memberId])],
                                  assignmentIds: [...new Set([...baseline.assignmentIds, assignmentId])],
                              }
                            : baseline,
                    cancelEditing: () => null,
                    persistRelationshipSuccess: () => null,
                    persistCustomPropertySuccess: () => null,
                },
            ],
            editingPropertyKey: [
                null as string | null,
                {
                    editProperty: (state, { property }) =>
                        property.editable !== false &&
                        (property.kind === 'relationship' || isCustomPropertyEditable(property.provenance))
                            ? property.key
                            : state,
                    cancelEditing: () => null,
                    persistCustomPropertySuccess: () => null,
                    persistRelationshipSuccess: () => null,
                },
            ],
            savingPropertyKey: [
                null as string | null,
                {
                    persistCustomProperty: (_, { propertyKey }) => propertyKey,
                    persistRelationship: (_, { propertyKey }) => propertyKey,
                    persistCustomPropertySuccess: () => null,
                    persistRelationshipSuccess: () => null,
                    persistCustomPropertyFailure: () => null,
                    persistRelationshipFailure: () => null,
                },
            ],
            propertySaveFailed: [
                false,
                {
                    editProperty: () => false,
                    cancelEditing: () => false,
                    persistCustomProperty: () => false,
                    persistRelationship: () => false,
                    persistCustomPropertyFailure: () => true,
                    persistRelationshipFailure: () => true,
                },
            ],
        })),
        selectors({
            propertyDataLoadFailed: [
                (s) => [s.resolvedPinnedProperties, s.sharedPropertyDataLoadFailed],
                (references: ResolvedPinnedAccountProperty[], failed: boolean): boolean =>
                    references.length > 0 && failed,
            ],
            resolvedPinnedProperties: [
                (s) => [s.sidebarPinnedProperties, s.availableDefinitions, s.configuredPropertyReferences],
                (
                    sidebar: ResolvedPinnedAccountProperty[],
                    definitions: AvailableDefinitions | null,
                    references: PinnedAccountProperty[] | null
                ): ResolvedPinnedAccountProperty[] =>
                    references === null
                        ? sidebar
                        : definitions
                          ? resolvePinnedProperties(references, definitions).resolved
                          : [],
            ],
            sidebarProperties: [
                (s) => [s.resolvedPinnedProperties, s.propertyData],
                (
                    pinned: ResolvedPinnedAccountProperty[],
                    data: AccountSidebarPropertyData | null
                ): AccountSidebarProperty[] =>
                    buildAccountSidebarProperties(
                        pinned,
                        data,
                        userHasAccess(AccessControlResourceType.CustomerAnalytics, AccessControlLevel.Editor)
                    ),
            ],
            availableMembers: [
                (s) => [s.members, s.propertyData],
                (
                    members: OrganizationMemberType[] | null,
                    data: AccountSidebarPropertyData | null
                ): AccountRelationshipMember[] => {
                    const byId = new Map<number, AccountRelationshipMember>()
                    for (const relationship of data?.relationships ?? []) {
                        if (relationship.user) {
                            byId.set(relationship.user.id, relationship.user)
                        }
                    }
                    for (const member of members ?? []) {
                        byId.set(member.user.id, {
                            id: member.user.id,
                            email: member.user.email,
                            name: member.user.first_name,
                        })
                    }
                    return [...byId.values()]
                },
            ],
            propertiesAvailable: [
                (s) => [
                    s.config,
                    s.availableDefinitions,
                    s.resolvedPinnedProperties,
                    s.propertyData,
                    s.configuredPropertyReferences,
                ],
                (
                    config: UserCustomerAnalyticsConfigApi | null,
                    definitions: AvailableDefinitions | null,
                    pinned: ResolvedPinnedAccountProperty[],
                    data: AccountSidebarPropertyData | null,
                    references: PinnedAccountProperty[] | null
                ): boolean =>
                    (references !== null || config !== null) &&
                    definitions !== null &&
                    (pinned.length === 0 || data !== null),
            ],
            propertiesLoadFailed: [
                (s) => [
                    s.configLoadFailed,
                    s.availableDefinitionsLoadFailed,
                    s.resolvedPinnedProperties,
                    s.propertyDataLoadFailed,
                    s.configuredPropertyReferences,
                ],
                (
                    configFailed: boolean,
                    definitionsFailed: boolean,
                    pinned: ResolvedPinnedAccountProperty[],
                    dataFailed: boolean,
                    references: PinnedAccountProperty[] | null
                ): boolean =>
                    (references === null && configFailed) || definitionsFailed || (pinned.length > 0 && dataFailed),
            ],
            // A failed load keeps the values of the previous successful load, so the blocking error
            // state is only for a panel that has nothing to show.
            propertiesPanelState: [
                (s) => [s.propertiesAvailable, s.propertiesLoadFailed],
                (available: boolean, failed: boolean): AccountPropertiesPanelState =>
                    available ? 'ready' : failed ? 'failed' : 'loading',
            ],
            propertiesRefreshFailed: [
                (s) => [s.propertiesAvailable, s.propertiesLoadFailed],
                (available: boolean, failed: boolean): boolean => available && failed,
            ],
        }),
        listeners(({ actions, props, values }) => {
            const baselineFor = (property: AccountRelationshipProperty): RelationshipEditBaseline => ({
                propertyKey: property.key,
                memberIds: property.members.map(({ id }) => id),
                assignmentIds: (values.propertyData?.relationships ?? [])
                    .filter((row) => row.definition.id === property.definition.id && !row.ended_at)
                    .map(({ id }) => id),
            })
            const refreshAccountsList = (): void => {
                dataNodeLogic.findMounted({ key: ACCOUNTS_TABLE_DATA_NODE_KEY })?.actions.loadData('force_async')
                dataNodeLogic.findMounted({ key: ACCOUNTS_METRICS_DATA_NODE_KEY })?.actions.loadData('force_async')
            }
            const refreshRelationships = (): void => {
                accountPropertyUpdatesLogic.actions.relationshipsUpdated(props.projectId, props.accountId)
                refreshAccountsList()
            }
            return {
                setConfiguredPropertyReferences: () => {
                    if (!values.propertyDataLoading) {
                        actions.loadPropertyData()
                    }
                },
                loadPropertyData: () => {
                    if (values.resolvedPinnedProperties.length > 0) {
                        actions.reloadPropertyData()
                    }
                },
                editProperty: ({ property }) => {
                    if (props.instanceId?.startsWith('view:') && values.editingPropertyKey === property.key) {
                        posthog.capture(AccountsEvents.AccountPropertyEditorOpened, {
                            source: 'account_view',
                            property_source: property.kind,
                        })
                    }
                    if (property.kind === 'relationship' && property.editable !== false) {
                        actions.setRelationshipEditBaseline(baselineFor(property))
                        actions.ensureAllMembersLoaded()
                    }
                },
                saveCustomProperty: ({ propertyKey, value, source }) => {
                    const property = values.sidebarProperties.find((row) => row.key === propertyKey)
                    if (
                        values.savingPropertyKey ||
                        property?.kind !== 'custom' ||
                        property.editable === false ||
                        !isCustomPropertyEditable(property.provenance)
                    ) {
                        return
                    }
                    actions.persistCustomProperty({ propertyKey, definitionId: property.definition.id, value, source })
                },
                saveRelationship: ({ propertyKey, memberIds, source }) => {
                    const property = values.sidebarProperties.find((row) => row.key === propertyKey)
                    if (values.savingPropertyKey || property?.kind !== 'relationship' || property.editable === false) {
                        return
                    }
                    const selected = [...new Set(memberIds)]
                    if (property.definition.is_single_holder !== false && selected.length > 1) {
                        return
                    }
                    const baseline =
                        values.relationshipEditBaseline?.propertyKey === propertyKey
                            ? values.relationshipEditBaseline
                            : baselineFor(property)
                    if (
                        selected.length === baseline.memberIds.length &&
                        selected.every((id) => baseline.memberIds.includes(id))
                    ) {
                        actions.cancelEditing()
                        actions.loadPropertyData()
                        return
                    }
                    actions.setRelationshipEditBaseline(baseline)
                    actions.persistRelationship({
                        propertyKey,
                        definitionId: property.definition.id,
                        memberIds: selected,
                        singleHolder: property.definition.is_single_holder !== false,
                        baseline,
                        source,
                    })
                },
                persistCustomPropertySuccess: ({ savedPropertyKey, payload }) => {
                    const property = values.sidebarProperties.find((row) => row.key === savedPropertyKey)
                    if (property?.kind === 'custom') {
                        // The property name and value stay out because they can hold customer data.
                        posthog.capture(AccountsEvents.CustomPropertyUpdated, {
                            display_type: property.definition.display_type,
                            workflow_reference: property.definition.has_workflow_reference,
                            source: payload?.source ?? 'account_sidebar',
                        })
                    }
                    actions.loadPropertyData()
                    refreshAccountsList()
                },
                persistRelationshipSuccess: ({ savedPropertyKey, payload }) => {
                    const property = values.sidebarProperties.find((row) => row.key === savedPropertyKey)
                    if (property?.kind === 'relationship') {
                        const memberIds = payload?.memberIds ?? []
                        posthog.capture(AccountsEvents.RoleAssigned, {
                            ...(payload?.source === 'account_view'
                                ? {}
                                : { role: ROLE_KEY_BY_NAME[property.definition.name] ?? property.definition.name }),
                            is_assigned: memberIds.length > 0,
                            assigned_user_id: memberIds.length === 1 ? memberIds[0] : null,
                            source: payload?.source ?? 'account_sidebar',
                        })
                    }
                    refreshRelationships()
                },
                persistCustomPropertyFailure: () => {
                    if (props.instanceId?.startsWith('view:')) {
                        posthog.capture(AccountsEvents.AccountPropertySaveFailed, {
                            source: 'account_view',
                            property_source: 'custom',
                        })
                    }
                },
                persistRelationshipFailure: () => {
                    if (props.instanceId?.startsWith('view:')) {
                        posthog.capture(AccountsEvents.AccountPropertySaveFailed, {
                            source: 'account_view',
                            property_source: 'relationship',
                        })
                    }
                    refreshRelationships()
                },
                [accountSidebarConfigLogic({ projectId: props.projectId }).actionTypes.loadConfigSuccess]: () =>
                    actions.loadPropertyData(),
                [accountSidebarConfigLogic({ projectId: props.projectId }).actionTypes.persistPinnedPropertiesSuccess]:
                    () => actions.loadPropertyData(),
                [accountSidebarConfigLogic({ projectId: props.projectId }).actionTypes.loadAvailableDefinitionsSuccess]:
                    () => actions.loadPropertyData(),
            }
        }),
        afterMount(({ actions }) => actions.loadPropertyData()),
        propsChanged(({ actions, props }, previousProps) => {
            const references = props.propertyReferences ?? []
            const previous = previousProps.propertyReferences ?? []
            const changed =
                (props.propertyReferences === undefined) !== (previousProps.propertyReferences === undefined) ||
                references.length !== previous.length ||
                references.some(
                    (reference, index) =>
                        reference.kind !== previous[index]?.kind || reference.id !== previous[index]?.id
                )
            if (changed) {
                actions.setConfiguredPropertyReferences(props.propertyReferences ?? null)
            }
        }),
    ])
