/**
 * An event the config leaves unset reaches this logic without a `kind`, sometimes with only a
 * `custom_name`. Its selector shows a button rather than a picker row that queries nothing.
 */
function configuredEventSeries(event: AnyEntityNode): SeriesNode[] | null {
    return event.kind ? [event] : null
}

// The pickers offer events and actions only, and edit one event each.
function toConfiguredEvent(series: SeriesNode[]): ActionsNode | EventsNode {
    return cleanSeriesNodes(series, MathAvailability.None)[0] as ActionsNode | EventsNode
}

