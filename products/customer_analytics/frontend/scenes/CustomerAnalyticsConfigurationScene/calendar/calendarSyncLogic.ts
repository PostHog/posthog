export const calendarSyncLogic = kea<calendarSyncLogicType>([
    path(['scenes', 'customerAnalytics', 'configuration', 'calendarSyncLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        syncNow: (integrationId: number) => ({ integrationId, triggeredAt: Date.now() }),
        triggerFinished: (integrationId: number) => ({ integrationId }),
        openBackfill: (integrationId: number) => {
            const today = dayjs().utc()
            return {
                integrationId,
                startDate: today.subtract(DEFAULT_BACKFILL_DAYS - 1, 'day').format(DATE_FORMAT),
                endDate: today.format(DATE_FORMAT),
            }
        },
        closeBackfill: true,
        setBackfillStartDate: (startDate: string | null) => ({ startDate }),
        setBackfillEndDate: (endDate: string | null) => ({ endDate }),
        submitBackfill: (integrationId: number, startDate: string, endDate: string) => ({
            integrationId,
            startDate,
            endDate,
            triggeredAt: Date.now(),
        }),
        backfillFinished: true,
    }),
    loaders(({ values }) => ({
        statuses: [
            [] as CalendarSyncStatusApi[],
            {
                loadStatuses: async (): Promise<CalendarSyncStatusApi[]> => {
                    try {
                        return [...(await calendarSyncList(String(values.currentTeamId)))]
                    } catch (error) {
                        posthog.captureException(error as Error, { scope: 'calendarSyncLogic.loadStatuses' })
                        return values.statuses
                    }
                },
            },
        ],
    })),
    reducers({
        triggeredAtByIntegrationId: [
            {} as Record<number, number>,
            {
                syncNow: (state, { integrationId, triggeredAt }) => ({ ...state, [integrationId]: triggeredAt }),
                submitBackfill: (state, { integrationId, triggeredAt }) => ({ ...state, [integrationId]: triggeredAt }),
                triggerFinished: (state, { integrationId }) =>
                    Object.fromEntries(Object.entries(state).filter(([id]) => Number(id) !== integrationId)),
            },
        ],
        backfillIntegrationId: [
            null as number | null,
            {
                openBackfill: (_, { integrationId }) => integrationId,
                closeBackfill: () => null,
            },
        ],
        backfillStartDate: [
            null as string | null,
            {
                openBackfill: (_, { startDate }) => startDate,
                setBackfillStartDate: (_, { startDate }) => startDate,
                closeBackfill: () => null,
            },
        ],
        backfillEndDate: [
            null as string | null,
            {
                openBackfill: (_, { endDate }) => endDate,
                setBackfillEndDate: (_, { endDate }) => endDate,
                closeBackfill: () => null,
            },
        ],
        backfillSubmitting: [
            false,
            {
                submitBackfill: () => true,
                backfillFinished: () => false,
            },
        ],
    }),
    selectors({
        statusByIntegrationId: [
            (s) => [s.statuses],
            (statuses: CalendarSyncStatusApi[]): Record<number, CalendarSyncStatusApi> =>
                Object.fromEntries(statuses.map((status) => [status.integration_id, status])),
        ],
        triggeringIntegrationIds: [
            (s) => [s.triggeredAtByIntegrationId],
            (triggeredAtByIntegrationId: Record<number, number>): number[] =>
                Object.keys(triggeredAtByIntegrationId).map(Number),
        ],
        backfillDateError: [
            (s) => [s.backfillStartDate, s.backfillEndDate],
            (startDate: string | null, endDate: string | null): string | null =>
                getGoogleAccountBackfillDateError(startDate, endDate),
        ],
    }),
    listeners(({ actions, values }) => ({
        // A sync in flight (or a trigger awaiting its server-side start marker) self-perpetuates
        // the status poll; the breakpoint cancels it on unmount.
        loadStatusesSuccess: async (_, breakpoint) => {
            for (const [id, triggeredAt] of Object.entries(values.triggeredAtByIntegrationId)) {
                const integrationId = Number(id)
                if (
                    values.statusByIntegrationId[integrationId]?.is_syncing ||
                    Date.now() - triggeredAt > TRIGGER_HANDOFF_TIMEOUT_MS
                ) {
                    actions.triggerFinished(integrationId)
                }
            }
            if (values.statuses.some((status) => status.is_syncing) || values.triggeringIntegrationIds.length > 0) {
                await breakpoint(POLL_INTERVAL_MS)
                actions.loadStatuses()
            }
        },
        submitBackfill: async ({ integrationId, startDate, endDate }) => {
            const dateError = getGoogleAccountBackfillDateError(startDate, endDate)
            if (dateError) {
                lemonToast.error(dateError)
                actions.triggerFinished(integrationId)
                actions.backfillFinished()
                return
            }
            try {
                const result = await calendarSyncBackfillCreate(String(values.currentTeamId), {
                    integration_id: integrationId,
                    start_date: startDate,
                    end_date: endDate,
                })
                if (result.status === 'already_running') {
                    lemonToast.info('A sync for this Google account is already running.')
                    actions.triggerFinished(integrationId)
                } else {
                    lemonToast.success('Google account backfill started. Emails and meetings will appear as it runs.')
                }
                if (values.backfillIntegrationId === integrationId) {
                    actions.closeBackfill()
                }
            } catch (error) {
                posthog.captureException(error as Error, { scope: 'calendarSyncLogic.submitBackfill' })
                lemonToast.error('Could not start the Google account backfill. Check the account and try again.')
                actions.triggerFinished(integrationId)
            } finally {
                actions.backfillFinished()
                actions.loadStatuses()
            }
        },
        syncNow: async ({ integrationId }) => {
            try {
                const result = await calendarSyncSyncNowCreate(String(values.currentTeamId), {
                    integration_id: integrationId,
                })
                if (result.status === 'already_running') {
                    lemonToast.info('A sync for this Google account is already running')
                    actions.triggerFinished(integrationId)
                } else {
                    lemonToast.success('Google account sync started. New meetings and emails appear in a few minutes.')
                }
            } catch (error) {
                posthog.captureException(error as Error, { scope: 'calendarSyncLogic.syncNow' })
                lemonToast.error('Could not start the Google account sync. Try again.')
                actions.triggerFinished(integrationId)
            } finally {
                actions.loadStatuses()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadStatuses()
    }),
])
