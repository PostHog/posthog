import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { dayjs } from 'lib/dayjs'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import {
    calendarSyncBackfillCreate,
    calendarSyncList,
    calendarSyncSyncNowCreate,
} from 'products/customer_analytics/frontend/generated/api'
import type { CalendarSyncStatusApi } from 'products/customer_analytics/frontend/generated/api.schemas'

const POLL_INTERVAL_MS = 5000
// start_workflow returns before the run writes its start marker, so keep the local
// "syncing" state alive until the server status takes over or this window expires.
const TRIGGER_HANDOFF_TIMEOUT_MS = 120_000
const DEFAULT_BACKFILL_DAYS = 90
const MAX_BACKFILL_LOOKBACK_DAYS = 365
const DATE_FORMAT = 'YYYY-MM-DD'

export function getGoogleAccountBackfillDateError(
    startDate: string | null,
    endDate: string | null,
    today: string = dayjs().utc().format(DATE_FORMAT)
): string | null {
    if (!startDate || !endDate) {
        return 'Select a start date and an end date.'
    }
    if (startDate < dayjs(today).subtract(MAX_BACKFILL_LOOKBACK_DAYS, 'day').format(DATE_FORMAT)) {
        return 'The start date must be within the last year.'
    }
    if (endDate > today) {
        return 'The end date cannot be after today.'
    }
    if (startDate > endDate) {
        return 'The end date must be on or after the start date.'
    }
    return null
}

