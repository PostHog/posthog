import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import posthog from 'posthog-js'

import api from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { userLogic } from 'scenes/userLogic'

import type { EmailConfigStatus } from 'products/conversations/frontend/scenes/settings/supportSettingsLogic'

import type { UserType } from '../../../../../../frontend/src/types'

export type CustomerEmailChannel = Pick<
    EmailConfigStatus,
    'id' | 'from_email' | 'forwarding_address' | 'connection_status' | 'setup_expires_at' | 'confirmation_available'
>

const FORWARDING_VERIFICATION_POLL_INTERVAL_MS = 3_000
const FORWARDING_VERIFICATION_POLL_ATTEMPTS = 10

function forwardingVerificationPollKey(channelId: string): string {
    return `forwardingVerificationPoll:${channelId}`
}

