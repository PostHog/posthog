    addEmailFormVisible: boolean
    channels: CustomerEmailChannel[]
    channelsLoadFailed: boolean
    channelsLoading: boolean
    connecting: boolean
    disconnectingChannelId: string | null
    emailDraft: string
    expandedChannelIds: string[]
    openingConfirmationChannelId: string | null
    verificationAwaitingChannelIds: string[]
    verificationTimedOutChannelIds: string[]
    verifyingChannelId: string | null
