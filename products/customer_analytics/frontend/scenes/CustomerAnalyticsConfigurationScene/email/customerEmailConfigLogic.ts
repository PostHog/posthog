export type customerEmailConfigLogicType = MakeLogicType<
    customerEmailConfigLogicValues,
    customerEmailConfigLogicActions
>

export const customerEmailConfigLogic = kea<customerEmailConfigLogicType>([
    path(['scenes', 'customerAnalytics', 'configuration', 'customerEmailConfigLogic']),
    connect(() => ({
        values: [userLogic, ['user']],
    })),
    actions({
        setAddEmailFormVisible: (visible: boolean) => ({ visible }),
        setEmailDraft: (email: string) => ({ email }),
        setExpandedChannelIds: (channelIds: string[]) => ({ channelIds }),
        loadChannels: (showError: boolean) => ({ showError }),
        loadChannelsSuccess: (channels: CustomerEmailChannel[]) => ({ channels }),
        loadChannelsFailure: true,
        connectEmail: true,
        connectEmailSuccess: (channel: CustomerEmailChannel) => ({ channel }),
        connectEmailFailure: true,
        openGmailConfirmation: (channelId: string) => ({ channelId }),
        openGmailConfirmationSuccess: true,
        openGmailConfirmationFailure: true,
        verifyForwarding: (channelId: string) => ({ channelId }),
        verifyForwardingSuccess: (channelId: string) => ({ channelId }),
        verifyForwardingFailure: true,
        verificationPollingTimedOut: (channelId: string) => ({ channelId }),
        disconnectEmail: (channelId: string) => ({ channelId }),
        disconnectEmailSuccess: (channelId: string) => ({ channelId }),
        disconnectEmailFailure: true,
    }),
    reducers({
        addEmailFormVisible: [
            false,
            {
                setAddEmailFormVisible: (_, { visible }) => visible,
                connectEmailSuccess: () => false,
            },
        ],
        expandedChannelIds: [
            [] as string[],
            {
                setExpandedChannelIds: (_, { channelIds }) => channelIds,
                connectEmailSuccess: (state, { channel }) => [...state, channel.id],
                disconnectEmailSuccess: (state, { channelId }) => state.filter((id) => id !== channelId),
            },
        ],
        emailDraft: [
            '',
            {
                setEmailDraft: (_, { email }) => email,
                connectEmailSuccess: () => '',
            },
        ],
        channels: [
            [] as CustomerEmailChannel[],
            {
                loadChannelsSuccess: (_, { channels }) => channels,
                connectEmailSuccess: (state, { channel }) => [...state, channel],
                disconnectEmailSuccess: (state, { channelId }) => state.filter((channel) => channel.id !== channelId),
            },
        ],
        channelsLoading: [
            true,
            {
                loadChannels: () => true,
                loadChannelsSuccess: () => false,
                loadChannelsFailure: () => false,
            },
        ],
        channelsLoadFailed: [
            false,
            {
                loadChannels: () => false,
                loadChannelsSuccess: () => false,
                loadChannelsFailure: () => true,
            },
        ],
        connecting: [
            false,
            {
                connectEmail: () => true,
                connectEmailSuccess: () => false,
                connectEmailFailure: () => false,
            },
        ],
        openingConfirmationChannelId: [
            null as string | null,
            {
                openGmailConfirmation: (_, { channelId }) => channelId,
                openGmailConfirmationSuccess: () => null,
                openGmailConfirmationFailure: () => null,
            },
        ],
        verifyingChannelId: [
            null as string | null,
            {
                verifyForwarding: (_, { channelId }) => channelId,
                verifyForwardingSuccess: () => null,
                verifyForwardingFailure: () => null,
            },
        ],
        verificationAwaitingChannelIds: [
            [] as string[],
            {
                verifyForwarding: (state, { channelId }) => state.filter((id) => id !== channelId),
                verifyForwardingSuccess: (state, { channelId }) => [...new Set([...state, channelId])],
                verificationPollingTimedOut: (state, { channelId }) => state.filter((id) => id !== channelId),
                loadChannelsSuccess: (state, { channels }) =>
                    state.filter((id) =>
                        channels.some(
                            (channel) => channel.id === id && channel.connection_status === 'pending_confirmation'
                        )
                    ),
                disconnectEmailSuccess: (state, { channelId }) => state.filter((id) => id !== channelId),
            },
        ],
        verificationTimedOutChannelIds: [
            [] as string[],
            {
                verifyForwarding: (state, { channelId }) => state.filter((id) => id !== channelId),
                verificationPollingTimedOut: (state, { channelId }) => [...new Set([...state, channelId])],
                loadChannelsSuccess: (state, { channels }) =>
                    state.filter((id) =>
                        channels.some(
                            (channel) => channel.id === id && channel.connection_status === 'pending_confirmation'
                        )
                    ),
                disconnectEmailSuccess: (state, { channelId }) => state.filter((id) => id !== channelId),
            },
        ],
        disconnectingChannelId: [
            null as string | null,
            {
                disconnectEmail: (_, { channelId }) => channelId,
                disconnectEmailSuccess: () => null,
                disconnectEmailFailure: () => null,
            },
        ],
    }),
    listeners(({ actions, cache, values }) => ({
        loadChannels: async ({ showError }) => {
            try {
                // nosemgrep: prefer-codegen-api
                const response = await api.get('api/conversations/v1/email/status?kind=customer_communication')
                actions.loadChannelsSuccess(response.configs ?? [])
            } catch (error) {
                posthog.captureException(error as Error, { scope: 'customerEmailConfigLogic.loadChannels' })
                actions.loadChannelsFailure()
                if (showError) {
                    lemonToast.error('Could not refresh your connected emails. Try again.')
                }
            }
        },
        loadChannelsSuccess: ({ channels }) => {
            for (const channel of channels) {
                if (channel.connection_status !== 'pending_confirmation') {
                    cache.disposables.dispose(forwardingVerificationPollKey(channel.id))
                }
            }
        },
        connectEmail: async () => {
            const email = values.emailDraft.trim().toLowerCase()
            if (!email || !values.user) {
                actions.connectEmailFailure()
                return
            }
            const displayName =
                [values.user.first_name, values.user.last_name].filter(Boolean).join(' ').trim() || values.user.email
            try {
                // nosemgrep: prefer-codegen-api
                const response = await api.create('api/conversations/v1/email/connect', {
                    from_email: email,
                    from_name: displayName,
                    kind: 'customer_communication',
                    owner_id: values.user.id,
                })
                actions.connectEmailSuccess(response.config)
                lemonToast.success('Forwarding setup started')
            } catch (error) {
                posthog.captureException(error as Error, { scope: 'customerEmailConfigLogic.connectEmail' })
                actions.connectEmailFailure()
                lemonToast.error('Could not connect this email. Check the address and try again.')
            }
        },
        openGmailConfirmation: async ({ channelId }) => {
            const confirmationWindow = window.open('about:blank', '_blank')
            try {
                // nosemgrep: prefer-codegen-api
                const response = await api.create('api/conversations/v1/email/confirm-forwarding', {
                    config_id: channelId,
                })
                actions.openGmailConfirmationSuccess()
                if (confirmationWindow) {
                    confirmationWindow.opener = null
                    confirmationWindow.location.replace(response.confirmation_url)
                } else {
                    window.location.assign(response.confirmation_url)
                }
                lemonToast.success('Gmail confirmation opened')
            } catch (error) {
                confirmationWindow?.close()
                posthog.captureException(error as Error, {
                    scope: 'customerEmailConfigLogic.openGmailConfirmation',
                })
                actions.openGmailConfirmationFailure()
                lemonToast.error('Could not open the Gmail confirmation. Check the setup and try again.')
            }
        },
        verifyForwarding: async ({ channelId }) => {
            try {
                // nosemgrep: prefer-codegen-api
                await api.create('api/conversations/v1/email/verify-forwarding', {
                    config_id: channelId,
                })
                if (cache.disposables.isDisposed) {
                    return
                }
                actions.verifyForwardingSuccess(channelId)
                lemonToast.success('Verification email sent')

                let pollAttempts = 0
                cache.disposables.add(() => {
                    const intervalId = window.setInterval(() => {
                        if (values.channelsLoading) {
                            return
                        }
                        pollAttempts += 1
                        if (pollAttempts > FORWARDING_VERIFICATION_POLL_ATTEMPTS) {
                            cache.disposables.dispose(forwardingVerificationPollKey(channelId))
                            actions.verificationPollingTimedOut(channelId)
                            return
                        }
                        actions.loadChannels(false)
                    }, FORWARDING_VERIFICATION_POLL_INTERVAL_MS)
                    return () => window.clearInterval(intervalId)
                }, forwardingVerificationPollKey(channelId))
                actions.loadChannels(false)
            } catch (error) {
                if (cache.disposables.isDisposed) {
                    return
                }
                posthog.captureException(error as Error, { scope: 'customerEmailConfigLogic.verifyForwarding' })
                actions.verifyForwardingFailure()
                lemonToast.error('Could not send the verification email. Wait a moment and try again.')
            }
        },
        disconnectEmail: async ({ channelId }) => {
            try {
                // nosemgrep: prefer-codegen-api
                await api.create('api/conversations/v1/email/disconnect', { config_id: channelId })
                cache.disposables.dispose(forwardingVerificationPollKey(channelId))
                actions.disconnectEmailSuccess(channelId)
                lemonToast.success('Email disconnected')
            } catch (error) {
                posthog.captureException(error as Error, { scope: 'customerEmailConfigLogic.disconnectEmail' })
                actions.disconnectEmailFailure()
                lemonToast.error('Could not disconnect this email. Try again.')
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadChannels(true)
    }),
])
