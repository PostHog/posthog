export const defaultPinnedAccountPropertiesLogic = kea<defaultPinnedAccountPropertiesLogicType>([
    path([
        'products',
        'customer_analytics',
        'frontend',
        'scenes',
        'CustomerAnalyticsConfigurationScene',
        'account',
        'defaultPinnedAccountPropertiesLogic',
    ]),
    connect(() => ({
        values: [
            teamLogic,
            ['customerAnalyticsConfig'],
            customPropertyDefinitionsLogic,
            [
                'definitions as customPropertyDefinitions',
                'definitionsLoading as customPropertyDefinitionsLoading',
                'definitionsLoadFailed as customPropertyDefinitionsLoadFailed',
            ],
            relationshipDefinitionsLogic,
            [
                'definitions as relationshipDefinitions',
                'definitionsLoading as relationshipDefinitionsLoading',
                'definitionsLoadFailed as relationshipDefinitionsLoadFailed',
            ],
        ],
        actions: [
            organizationLogic,
            ['loadCurrentOrganizationSuccess'],
            teamLogic,
            ['updateCurrentTeam', 'updateCurrentTeamSuccess', 'updateCurrentTeamFailure'],
            customPropertyDefinitionsLogic,
            ['loadDefinitions as loadCustomPropertyDefinitions'],
            relationshipDefinitionsLogic,
            ['loadDefinitions as loadRelationshipDefinitions'],
        ],
    })),
    actions({
        openConfigurator: true,
        closeConfigurator: true,
        setSelectedRoleId: (roleId: string | null) => ({ roleId }),
        setDraftPinnedPropertyKeys: (keys: string[]) => ({ keys }),
        saveDefaultPinnedProperties: true,
        retryDefinitions: true,
        startSaving: true,
        saveDefaultPinnedPropertiesSuccess: true,
        saveDefaultPinnedPropertiesFailure: true,
    }),
    loaders(({ values, cache }) => ({
        rolesState: [
            { roles: [], complete: false } as LoadedRolesState,
            {
                loadRoles: async (): Promise<LoadedRolesState> => {
                    if (!ApiConfig.hasCurrentOrganizationId()) {
                        // The loadCurrentOrganizationSuccess listener runs this load again when the ID is known.
                        cache.rolesLoadSkipped = true
                        return values.rolesState
                    }
                    const roles: RoleType[] = []
                    const seenNextUrls = new Set<string>()
                    let page: PaginatedResponse<RoleType> | null = await api.roles.list()
                    while (page) {
                        roles.push(...(page.results ?? []))
                        if (!page.next) {
                            return { roles, complete: true }
                        }
                        if (seenNextUrls.has(page.next)) {
                            return { roles, complete: false }
                        }
                        seenNextUrls.add(page.next)
                        // nosemgrep: prefer-codegen-api -- Follows the pagination URL the server returns.
                        page = await api.get<PaginatedResponse<RoleType>>(page.next)
                    }
                    return { roles, complete: false }
                },
            },
        ],
    })),
    reducers({
        rolesLoadedComplete: [
            false,
            {
                loadRoles: () => false,
                loadRolesSuccess: (_, { rolesState }) => rolesState.complete,
                loadRolesFailure: () => false,
            },
        ],
        selectedRoleId: [
            null as string | null,
            {
                setSelectedRoleId: (_, { roleId }) => roleId,
            },
        ],
        isOpen: [
            false,
            {
                openConfigurator: () => true,
                closeConfigurator: () => false,
                setSelectedRoleId: () => false,
                saveDefaultPinnedPropertiesSuccess: () => false,
            },
        ],
        draftPinnedPropertyKeys: [
            [] as string[],
            {
                setDraftPinnedPropertyKeys: (_, { keys }) => keys,
            },
        ],
        saving: [
            false,
            {
                startSaving: () => true,
                saveDefaultPinnedPropertiesSuccess: () => false,
                saveDefaultPinnedPropertiesFailure: () => false,
            },
        ],
        saveFailed: [
            false,
            {
                openConfigurator: () => false,
                startSaving: () => false,
                saveDefaultPinnedPropertiesSuccess: () => false,
                saveDefaultPinnedPropertiesFailure: () => true,
            },
        ],
    }),
    selectors({
        roles: [(s) => [s.rolesState], (rolesState: LoadedRolesState): RoleType[] => rolesState.roles],
        rolesLoading: [(s) => [s.rolesStateLoading], (loading: boolean): boolean => loading],
        defaultPinnedProperties: [
            (s) => [s.customerAnalyticsConfig, s.selectedRoleId],
            (config: CustomerAnalyticsConfig, selectedRoleId: string | null): PinnedAccountPropertyApi[] =>
                (selectedRoleId === null
                    ? (config.default_pinned_properties ?? [])
                    : ((config.role_default_pinned_properties ?? []).find(({ role_id }) => role_id === selectedRoleId)
                          ?.pinned_properties ?? [])
                ).map(({ kind, id }) => ({ kind, id })),
        ],
        selectedRole: [
            (s) => [s.roles, s.selectedRoleId],
            (roles: RoleType[], selectedRoleId: string | null): RoleType | null =>
                roles.find(({ id }) => id === selectedRoleId) ?? null,
        ],
        propertyOptions: [
            (s) => [s.customPropertyDefinitions, s.relationshipDefinitions],
            (
                customProperties: CustomPropertyDefinitionApi[],
                relationships: AccountRelationshipDefinitionApi[]
            ): AccountPropertyOption[] =>
                buildPinnedPropertyOptions({
                    customProperties: customProperties.filter(({ target_type }) => target_type === 'account'),
                    relationships,
                }),
        ],
        resolvedPinnedPropertyKeys: [
            (s) => [s.defaultPinnedProperties, s.propertyOptions],
            (references: PinnedAccountPropertyApi[], options: AccountPropertyOption[]): string[] => {
                const availableKeys = new Set(options.map(({ key }) => key))
                return references.map(pinnedPropertyToConfiguratorKey).filter((key) => availableKeys.has(key))
            },
        ],
        stalePinnedProperties: [
            (s) => [s.defaultPinnedProperties, s.propertyOptions],
            (references: PinnedAccountPropertyApi[], options: AccountPropertyOption[]): PinnedAccountPropertyApi[] => {
                const availableKeys = new Set(options.map(({ key }) => key))
                return references.filter((reference) => !availableKeys.has(pinnedPropertyToConfiguratorKey(reference)))
            },
        ],
        definitionsLoading: [
            (s) => [s.customPropertyDefinitionsLoading, s.relationshipDefinitionsLoading],
            (customPropertiesLoading: boolean, relationshipsLoading: boolean): boolean =>
                customPropertiesLoading || relationshipsLoading,
        ],
        definitionsLoadFailed: [
            (s) => [s.customPropertyDefinitionsLoadFailed, s.relationshipDefinitionsLoadFailed],
            (customPropertiesLoadFailed: boolean, relationshipsLoadFailed: boolean): boolean =>
                customPropertiesLoadFailed || relationshipsLoadFailed,
        ],
        canSave: [
            (s) => [
                s.isOpen,
                s.saving,
                s.definitionsLoading,
                s.definitionsLoadFailed,
                s.draftPinnedPropertyKeys,
                s.defaultPinnedProperties,
            ],
            (
                isOpen: boolean,
                saving: boolean,
                definitionsLoading: boolean,
                definitionsLoadFailed: boolean,
                draftKeys: string[],
                savedReferences: PinnedAccountPropertyApi[]
            ): boolean => {
                const savedKeys = savedReferences.map(pinnedPropertyToConfiguratorKey)
                return (
                    isOpen &&
                    !saving &&
                    !definitionsLoading &&
                    !definitionsLoadFailed &&
                    (draftKeys.length !== savedKeys.length || draftKeys.some((key, index) => key !== savedKeys[index]))
                )
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadCurrentOrganizationSuccess: () => {
            if (cache.rolesLoadSkipped) {
                cache.rolesLoadSkipped = false
                actions.loadRoles()
            }
        },
        openConfigurator: () => {
            actions.setDraftPinnedPropertyKeys(values.resolvedPinnedPropertyKeys)
        },
        closeConfigurator: () => {
            actions.setDraftPinnedPropertyKeys(values.resolvedPinnedPropertyKeys)
        },
        retryDefinitions: () => {
            actions.loadCustomPropertyDefinitions()
            actions.loadRelationshipDefinitions()
        },
        saveDefaultPinnedProperties: () => {
            if (!values.canSave) {
                return
            }
            actions.startSaving()
            const pinnedProperties = configuratorKeysToPinnedProperties(values.draftPinnedPropertyKeys)
            const { selectedRoleId } = values
            const activeRoleIds = values.rolesLoadedComplete ? new Set(values.roles.map(({ id }) => id)) : null
            actions.updateCurrentTeam({
                customer_analytics_config: (selectedRoleId === null
                    ? { default_pinned_properties: pinnedProperties }
                    : {
                          role_default_pinned_properties: [
                              ...(values.customerAnalyticsConfig.role_default_pinned_properties ?? []).filter(
                                  ({ role_id }) =>
                                      role_id !== selectedRoleId &&
                                      (activeRoleIds === null || activeRoleIds.has(role_id))
                              ),
                              { role_id: selectedRoleId, pinned_properties: pinnedProperties },
                          ],
                      }) as CustomerAnalyticsConfig,
            })
        },
        updateCurrentTeamSuccess: ({ payload }) => {
            const config = payload?.customer_analytics_config
            if (
                config?.default_pinned_properties !== undefined ||
                config?.role_default_pinned_properties !== undefined
            ) {
                actions.saveDefaultPinnedPropertiesSuccess()
            }
        },
        updateCurrentTeamFailure: () => {
            if (values.saving) {
                actions.saveDefaultPinnedPropertiesFailure()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRoles()
    }),
])
