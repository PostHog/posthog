export type personsSceneLogicType = MakeLogicType<
    personsSceneLogicValues,
    personsSceneLogicActions,
    Record<string, any>,
    personsSceneLogicMeta
>

export const personsSceneLogic = kea<personsSceneLogicType>([
    path(['scenes', 'persons', 'personsSceneLogic']),

    connect({ values: [teamLogic, ['currentTeam']] }),

    actions({
        setQuery: (query: DataTableNode) => ({ query }),
        setShowDisplayNameNudge: (showDisplayNameNudge: boolean) => ({ showDisplayNameNudge }),
        setIsBannerLoading: (isBannerLoading: boolean) => ({ isBannerLoading }),
    }),

    reducers({
        query: [
            PEOPLE_LIST_DEFAULT_QUERY,
            {
                setQuery: (state, { query }) => ({
                    ...query,
                    defaultColumns: query.defaultColumns ?? state.defaultColumns,
                }),
            },
        ],
        showDisplayNameNudge: [
            false,
            {
                setShowDisplayNameNudge: (_, { showDisplayNameNudge }) => showDisplayNameNudge,
            },
        ],
        isBannerLoading: [
            false,
            {
                setIsBannerLoading: (_, { isBannerLoading }) => isBannerLoading,
            },
        ],
    }),

    selectors({
        defaultQuery: [
            (s) => [s.currentTeam],
            (currentTeam: null | import('~/types').TeamPublicType | import('~/types').TeamType): DataTableNode =>
                buildDefaultQuery(currentTeam?.extra_settings?.person_last_seen_at_enabled === true),
        ],
        defaultColumns: [
            (s) => [s.defaultQuery],
            (defaultQuery: DataTableNode): string[] => defaultQuery.defaultColumns ?? [],
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: 'persons',
                    name: sceneConfigurations[Scene.Persons].name,
                    iconType: sceneConfigurations[Scene.Persons].iconType || 'default_icon_type',
                },
            ],
        ],
    }),

    trackedActionToUrl(({ values }) => ({
        setQuery: () => {
            if (removeProjectIdIfPresent(router.values.location.pathname) === urls.persons()) {
                return [
                    urls.persons(),
                    {},
                    equal(values.query, values.defaultQuery) ? {} : { q: values.query },
                    { replace: true },
                ]
            }
        },
    })),

    urlToAction(({ actions, values }) => ({
        [urls.persons()]: (_, __, { q: queryParam }): void => {
            if (!equal(queryParam, values.query)) {
                // Command K links here with `?search=`. The router parses `001234` as the number 1234 and
                // `0` as falsy, so read the raw string: person and distinct IDs keep their exact text.
                const search = new URLSearchParams(router.values.location.search).get('search')
                if (!queryParam && search) {
                    actions.setQuery({
                        ...values.defaultQuery,
                        source: { ...(values.defaultQuery.source as ActorsQuery), search },
                        defaultColumns: values.defaultColumns,
                    })
                } else if (!queryParam) {
                    actions.setQuery({
                        ...values.defaultQuery,
                        defaultColumns: values.defaultColumns,
                    })
                } else {
                    if (typeof queryParam === 'object') {
                        actions.setQuery({
                            ...queryParam,
                            defaultColumns: values.defaultColumns,
                        })
                    } else {
                        lemonToast.error('Invalid query in URL')
                        console.error({ queryParam })
                    }
                }
            }
        },
    })),
])
