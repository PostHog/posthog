export const PEOPLE_LIST_CONTEXT_KEY = 'people-list'

function buildDefaultQuery(personLastSeenAtEnabled: boolean): DataTableNode {
    const columns = [...defaultDataTableColumns(NodeKind.ActorsQuery, personLastSeenAtEnabled), 'person.$delete']
    return {
        kind: NodeKind.DataTableNode,
        source: {
            kind: NodeKind.ActorsQuery,
            tags: { productKey: ProductKey.CUSTOMER_ANALYTICS },
            select: columns,
        },
        defaultColumns: columns,
        full: true,
        propertiesViaUrl: true,
        contextKey: PEOPLE_LIST_CONTEXT_KEY,
    } as DataTableNode
}

export const PEOPLE_LIST_DEFAULT_QUERY = buildDefaultQuery(false)

// The scene's real default gains a `last_seen_at` column when the team turns on that setting,
// so a caller that checks for an untouched default has to accept both shapes.
const PEOPLE_LIST_DEFAULT_QUERY_WITH_LAST_SEEN_AT = buildDefaultQuery(true)

/** Takes an `ActorsQuery` source, not the whole `DataTableNode`. */
export function isPeopleListDefaultQuery(source: unknown): boolean {
    return (
        equal(source, PEOPLE_LIST_DEFAULT_QUERY.source) ||
        equal(source, PEOPLE_LIST_DEFAULT_QUERY_WITH_LAST_SEEN_AT.source)
    )
}

