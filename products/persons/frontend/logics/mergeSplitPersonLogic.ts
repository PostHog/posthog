/**
 * `posthog/api/person.py` rejects a split under this field when a selected distinct ID is no
 * longer on the person. The modal builds its options once, so an ingestion-side merge, another
 * tab, or the API can move one off between opening the modal and submitting it.
 */
function isStaleDistinctIdError(error: unknown): boolean {
    return error instanceof ApiError && error.status === 400 && error.attr === 'distinct_ids_to_split'
}

async function loadCurrentDistinctIds(personId: string | undefined): Promise<string[] | null> {
    if (personId === undefined) {
        return null
    }
    try {
        // The persons route is nested under `/api/projects/`, but it is registered with a
        // `team_id` parent lookup, so the path segment is an environment id. A child environment
        // has a different project id, which would resolve to another environment and 404.
        const person = await personsRetrieve(String(ApiConfig.getCurrentTeamId()), personId)
        return [...person.distinct_ids]
    } catch {
        // Without the current list the modal cannot name the stale IDs, but it still recovers.
        return null
    }
}

export const mergeSplitPersonLogic = kea<mergeSplitPersonLogicType>([
    props({} as SplitPersonLogicProps),
    key((props) => `${props.person.id ?? 'new'}`),
    path((key) => ['scenes', 'persons', 'mergeSplitPersonLogic', key]),
    connect((props: SplitPersonLogicProps) => ({
        actions: [
            personsLogic({ syncWithUrl: true, urlId: props.urlId }),
            ['setListFilters', 'loadPersons', 'setPerson', 'setSplitMergeModalShown'],
        ],
        values: [personsLogic({ syncWithUrl: true, urlId: props.urlId }), ['persons']],
    })),
    actions({
        setSelectedPersonToAssignSplit: (id: string) => ({ id }),
        setSplitMode: (mode: SplitMode) => ({ mode }),
        setDistinctIdsToSplit: (ids: string[]) => ({ ids }),
        splitRejected: (staleDistinctIds: string[], distinctIds: string[] | null) => ({
            staleDistinctIds,
            distinctIds,
        }),
        cancel: true,
    }),
    loaders(({ values, actions }) => ({
        executed: [
            false,
            {
                execute: async () => {
                    const payload =
                        values.splitMode === 'partial'
                            ? { distinct_ids_to_split: values.distinctIdsToSplit }
                            : values.selectedPersonToAssignSplit
                              ? { main_distinct_id: values.selectedPersonToAssignSplit }
                              : {}
                    let splitAction: { success?: boolean }
                    try {
                        // The split keeps the legacy flat route, because moving the working
                        // path onto the environment-scoped route is a separate change.
                        // nosemgrep: prefer-codegen-api
                        splitAction = await api.create('api/person/' + values.person.id + '/split/', payload)
                    } catch (error) {
                        if (!isStaleDistinctIdError(error)) {
                            throw error
                        }
                        // Handled in the modal, so the loader resolves instead of failing: a
                        // failing loader toasts the raw backend string and reports a user-input
                        // error to error tracking.
                        const distinctIds = await loadCurrentDistinctIds(values.person.id)
                        const staleDistinctIds = distinctIds
                            ? values.distinctIdsToSplit.filter((id) => !distinctIds.includes(id))
                            : []
                        actions.splitRejected(staleDistinctIds, distinctIds)
                        // Null rather than zero when the refresh failed: the rejection proves at
                        // least one ID is stale, so a count of zero would misreport it.
                        eventUsageLogic.actions.reportPersonSplitRejected(distinctIds ? staleDistinctIds.length : null)
                        return false
                    }
                    if (splitAction.success) {
                        lemonToast.success(
                            'Person succesfully split. This may take up to a couple of minutes to complete.'
                        )
                        eventUsageLogic.actions.reportPersonSplit(values.person.distinct_ids.length)
                        actions.setSplitMergeModalShown(false)
                        router.actions.push('/persons')
                        return true
                    }
                    return false
                },
            },
        ],
    })),
    reducers(({ props }) => ({
        person: [
            props.person,
            {
                splitRejected: (state, { distinctIds }) =>
                    distinctIds ? { ...state, distinct_ids: distinctIds } : state,
            },
        ],
        selectedPersonToAssignSplit: [
            null as null | string,
            {
                setSelectedPersonToAssignSplit: (_, { id }) => id,
            },
        ],
        splitMode: [
            'all' as SplitMode,
            {
                setSplitMode: (_, { mode }) => mode,
            },
        ],
        distinctIdsToSplit: [
            [] as string[],
            {
                setDistinctIdsToSplit: (_, { ids }) => ids,
                splitRejected: (state, { staleDistinctIds }) => state.filter((id) => !staleDistinctIds.includes(id)),
            },
        ],
        /** Null until a split is rejected, and empty when the refresh could not name which IDs moved off. */
        staleDistinctIds: [
            null as string[] | null,
            {
                splitRejected: (_, { staleDistinctIds }) => staleDistinctIds,
                execute: () => null,
                setDistinctIdsToSplit: () => null,
                setSplitMode: () => null,
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        setListFilters: () => {
            actions.loadPersons()
        },
        cancel: () => {
            if (!values.executedLoading) {
                actions.setSplitMergeModalShown(false)
            }
        },
    })),
    events(({ actions }) => ({
        afterMount: [actions.loadPersons],
    })),
])
