export const personEmailsLogic = kea<personEmailsLogicType>([
    path(['scenes', 'persons', 'personEmailsLogic']),
    props({} as PersonEmailsLogicProps),
    key((props) => `${props.teamId}-${props.personId}`),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags']], actions: [featureFlagLogic, ['setFeatureFlags']] })),
    actions({
        lookUpOutcomes: (emails: MessageAsset[]) => ({ emails }),
        stopLookups: true,
        setLookup: (id: string, lookup: EmailLookup) => ({ id, lookup }),
        openEmail: (asset: MessageAsset) => ({ asset }),
        waitToOpen: (asset: MessageAsset) => ({ asset }),
        openSendPage: (id: string) => ({ id }),
        preview: (asset: MessageAsset) => ({ asset }),
        closePreview: true,
    }),
    lazyLoaders(({ props }) => ({
        emails: [
            [] as MessageAsset[],
            {
                loadEmails: async () => {
                    if (!props.personId) {
                        return []
                    }
                    return await getPersonMessageAssets(props.teamId, props.personId)
                },
            },
        ],
    })),
    reducers({
        lookups: [
            null as Record<string, EmailLookup> | null,
            {
                lookUpOutcomes: (_, { emails }) =>
                    Object.fromEntries(emails.map((email) => [email.invocation_id, 'looking' as const])),
                stopLookups: () => null,
                setLookup: (state, { id, lookup }) => (state ? { ...state, [id]: lookup } : state),
            },
        ],
        waitingToOpen: [
            null as MessageAsset | null,
            {
                waitToOpen: (_, { asset }) => asset,
                openSendPage: () => null,
                preview: () => null,
            },
        ],
        previewed: [
            null as MessageAsset | null,
            {
                preview: (_, { asset }) => asset,
                closePreview: () => null,
            },
        ],
    }),
    selectors({
        outcomesShown: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean =>
                !!featureFlags[FEATURE_FLAGS.WORKFLOWS_EMAIL_SEND_TIMELINE] &&
                !!featureFlags[FEATURE_FLAGS.WORKFLOWS_TRANSACTIONAL_EMAIL_API],
        ],
        outcomeColumnShown: [
            (s) => [s.outcomesShown, s.lookups],
            (outcomesShown: boolean, lookups: Record<string, EmailLookup> | null): boolean =>
                outcomesShown && Object.values(lookups ?? {}).some((lookup) => lookup !== 'not_logged'),
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        const open = (asset: MessageAsset): void => {
            const lookup = values.outcomesShown ? values.lookups?.[asset.invocation_id] : undefined
            if (lookup === 'looking') {
                actions.waitToOpen(asset)
            } else if (lookup && isEmailOutcome(lookup)) {
                actions.openSendPage(asset.invocation_id)
            } else {
                actions.preview(asset)
            }
        }
        return {
            loadEmailsSuccess: ({ emails }) => {
                if (values.outcomesShown) {
                    actions.lookUpOutcomes(emails)
                }
            },
            setFeatureFlags: () => {
                if (!values.outcomesShown) {
                    if (values.lookups) {
                        actions.stopLookups()
                    }
                } else if (!values.lookups && !values.emailsLoading && values.emails.length) {
                    actions.lookUpOutcomes(values.emails)
                }
            },
            stopLookups: () => {
                if (values.waitingToOpen) {
                    actions.preview(values.waitingToOpen)
                }
            },
            lookUpOutcomes: async ({ emails }, breakpoint) => {
                const oldest = dayjs.utc().subtract(LOG_RETENTION_DAYS, 'day')
                const queue = [...new Set(emails.map((email) => email.invocation_id))]
                const lookUpNext = async (): Promise<void> => {
                    for (let id = queue.shift(); id && values.outcomesShown; id = queue.shift()) {
                        let lookup: EmailLookup
                        try {
                            const page = await transactionalEmailLogList(String(props.teamId), {
                                search: id,
                                date_from: oldest.toISOString(),
                                limit: 1,
                            })
                            const send = page.results.find((result) => result.message_id === id)
                            lookup = send ? emailOutcome(send) : 'not_logged'
                        } catch {
                            lookup = 'unavailable'
                        }
                        breakpoint()
                        if (cache.disposables.isDisposed) {
                            return
                        }
                        actions.setLookup(id, lookup)
                    }
                }
                await Promise.all(Array.from({ length: LOOKUP_CONCURRENCY }, lookUpNext))
            },
            openEmail: ({ asset }) => open(asset),
            setLookup: ({ id }) => {
                if (values.waitingToOpen?.invocation_id === id) {
                    open(values.waitingToOpen)
                }
            },
            openSendPage: ({ id }) => router.actions.push(urls.transactionalEmailLogEntry(id)),
        }
    }),
])
