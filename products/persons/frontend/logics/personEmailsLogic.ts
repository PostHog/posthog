import { MakeLogicType, connect, kea, key, listeners, path, props } from 'kea'
import { lazyLoaders, loaders } from 'kea-loaders'

import { FEATURE_FLAGS } from 'lib/constants'
import { dayjs } from 'lib/dayjs'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'

import { transactionalEmailLogList } from 'products/messaging/frontend/generated/api'
import { LOG_RETENTION_DAYS } from 'products/workflows/frontend/Transactional/log/transactionalEmailLogLogic'
import { getPersonMessageAssets, MessageAsset } from 'products/workflows/frontend/Workflows/messageAssetsApi'

import type { FeatureFlagsSet } from '../../../../frontend/src/lib/logic/featureFlagLogic'

export type EmailOutcome = 'clicked' | 'opened' | 'not_opened'

const RECIPIENT_LOG_LIMIT = 100

export interface PersonEmailsLogicProps {
    teamId: number
    personId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface personEmailsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    emails: MessageAsset[]
    emailsLoading: boolean
    outcomes: Record<string, EmailOutcome> | null
    outcomesLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface personEmailsLogicActions {
    loadEmails: () => any
    loadEmailsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadEmailsSuccess: (
        emails: MessageAsset[],
        payload?: any
    ) => {
        emails: MessageAsset[]
        payload?: any
    }
    loadOutcomes: (emails: MessageAsset[]) => MessageAsset[]
    loadOutcomesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadOutcomesSuccess: (
        outcomes: Record<string, EmailOutcome>,
        payload?: MessageAsset[]
    ) => {
        outcomes: Record<string, EmailOutcome>
        payload?: MessageAsset[]
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface personEmailsLogicMeta {
    key: string
}

export type personEmailsLogicType = MakeLogicType<
    personEmailsLogicValues,
    personEmailsLogicActions,
    PersonEmailsLogicProps,
    personEmailsLogicMeta
>

export const personEmailsLogic = kea<personEmailsLogicType>([
    path(['scenes', 'persons', 'personEmailsLogic']),
    props({} as PersonEmailsLogicProps),
    key((props) => `${props.teamId}-${props.personId}`),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags']] })),
    lazyLoaders(({ props }) => ({
        emails: [
            [] as MessageAsset[],
            {
                loadEmails: async () => {
                    if (!props.personId) {
                        return []
                    }
                    return await getPersonMessageAssets(props.teamId, props.personId)
                },
            },
        ],
    })),
    loaders(({ props }) => ({
        outcomes: [
            null as Record<string, EmailOutcome> | null,
            {
                loadOutcomes: async (emails: MessageAsset[]) => {
                    const oldest = dayjs().subtract(LOG_RETENTION_DAYS, 'day')
                    const recipients = new Set(
                        emails
                            .filter((email) => email.recipient && dayjs(email.sent_at).isAfter(oldest))
                            .map((email) => email.recipient.toLowerCase())
                    )
                    const outcomes: Record<string, EmailOutcome> = {}
                    for (const recipient of recipients) {
                        const page = await transactionalEmailLogList(String(props.teamId), {
                            search: recipient,
                            date_from: oldest.toISOString(),
                            limit: RECIPIENT_LOG_LIMIT,
                        })
                        for (const send of page.results) {
                            if (send.recipient.toLowerCase() === recipient) {
                                outcomes[send.message_id] = send.clicked
                                    ? 'clicked'
                                    : send.opened
                                      ? 'opened'
                                      : 'not_opened'
                            }
                        }
                    }
                    return outcomes
                },
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        loadEmailsSuccess: ({ emails }) => {
            if (
                values.featureFlags[FEATURE_FLAGS.WORKFLOWS_EMAIL_SEND_TIMELINE] &&
                values.featureFlags[FEATURE_FLAGS.WORKFLOWS_TRANSACTIONAL_EMAIL_API]
            ) {
                actions.loadOutcomes(emails)
            }
        },
    })),
])
