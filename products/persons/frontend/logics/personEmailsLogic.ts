import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { lazyLoaders } from 'kea-loaders'
import { router } from 'kea-router'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { projectLogic } from 'scenes/projectLogic'

import { transactionalEmailLogRetrieve } from 'products/messaging/frontend/generated/api'
import { transactionalSendPageUrl } from 'products/workflows/frontend/Transactional/transactionalEmailUrl'
import { getPersonMessageAssets, MessageAsset } from 'products/workflows/frontend/Workflows/messageAssetsApi'

export interface PersonEmailsLogicProps {
    teamId: number
    personId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface personEmailsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentProjectId: number | null // projectLogic
    emails: MessageAsset[]
    emailsLoading: boolean
    openingEmail: boolean
    previewedEmail: MessageAsset | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface personEmailsLogicActions {
    loadEmails: () => any
    loadEmailsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadEmailsSuccess: (
        emails: MessageAsset[],
        payload?: any
    ) => {
        emails: MessageAsset[]
        payload?: any
    }
    openEmail: (asset: MessageAsset) => {
        asset: MessageAsset
    }
    openSendPage: (url: string) => {
        url: string
    }
    previewEmail: (asset: MessageAsset | null) => {
        asset: MessageAsset | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface personEmailsLogicMeta {
    key: string
}

export type personEmailsLogicType = MakeLogicType<
    personEmailsLogicValues,
    personEmailsLogicActions,
    PersonEmailsLogicProps,
    personEmailsLogicMeta
>

export const personEmailsLogic = kea<personEmailsLogicType>([
    path(['scenes', 'persons', 'personEmailsLogic']),
    props({} as PersonEmailsLogicProps),
    key((props) => `${props.teamId}-${props.personId}`),
    connect(() => ({ values: [projectLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']] })),
    actions({
        openEmail: (asset: MessageAsset) => ({ asset }),
        previewEmail: (asset: MessageAsset | null) => ({ asset }),
        openSendPage: (url: string) => ({ url }),
    }),
    reducers({
        previewedEmail: [
            null as MessageAsset | null,
            {
                previewEmail: (_, { asset }) => asset,
            },
        ],
        openingEmail: [
            false,
            {
                openEmail: () => true,
                previewEmail: () => false,
                openSendPage: () => false,
            },
        ],
    }),
    lazyLoaders(({ props }) => ({
        emails: [
            [] as MessageAsset[],
            {
                loadEmails: async () => {
                    if (!props.personId) {
                        return []
                    }
                    return await getPersonMessageAssets(props.teamId, props.personId)
                },
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        openEmail: async ({ asset }, breakpoint) => {
            const sendPages =
                !!values.featureFlags[FEATURE_FLAGS.WORKFLOWS_EMAIL_SEND_TIMELINE] &&
                !!values.featureFlags[FEATURE_FLAGS.WORKFLOWS_TRANSACTIONAL_EMAIL_API]
            const url = sendPages ? transactionalSendPageUrl(asset) : null
            if (!url || values.currentProjectId === null) {
                actions.previewEmail(asset)
                return
            }
            let logged = true
            try {
                await transactionalEmailLogRetrieve(String(values.currentProjectId), asset.invocation_id)
            } catch (error: any) {
                logged = error?.status !== 404
            }
            breakpoint()
            if (logged) {
                actions.openSendPage(url)
            } else {
                actions.previewEmail(asset)
            }
        },
        openSendPage: ({ url }) => {
            router.actions.push(url)
        },
    })),
])
