"""The default auth type of each warehouse source credential kind.

A row of a credential kind stores its auth type in `config["auth_type"]` only when it is not the default
of the kind, so the default is stored data. The result is frozen in the generated file
`facade/credential_auth_types.py`, and the warehouse product registers it with the integrations SDK at
startup. `generate_source_field_classification` writes that file, and a test fails when it is out of date.

Each source gives the auth type of its kind with `credential_auth_type` on its class. The default,
`derive_credential_auth_type`, comes from the source's connection fields, the same split as
`job_input_classification`:

- `oauth`: the source has an OAuth field and no typed-in connection field.
- `token`: the source has exactly one typed-in field, and it is a secret.
- `credentials`: every other source.
"""

from collections.abc import Iterator
from pathlib import Path

from products.warehouse_sources.backend.facade.credential_auth_types import CREDENTIAL_AUTH_TYPES
from products.warehouse_sources.backend.facade.source_config import (
    SourceConfig,
    SourceFieldInputConfig,
    SourceFieldSelectConfig,
)
from products.warehouse_sources.backend.temporal.data_imports.sources.common.base import FieldType
from products.warehouse_sources.backend.temporal.data_imports.sources.common.credential_kind import merge_append_only
from products.warehouse_sources.backend.temporal.data_imports.sources.common.job_input_classification import (
    JobInputKind,
    field_kind,
    reference_option_values,
)
from products.warehouse_sources.backend.temporal.data_imports.sources.common.registry import SourceRegistry

CREDENTIAL_AUTH_TYPES_PATH = Path(__file__).resolve().parents[4] / "facade" / "credential_auth_types.py"

OAUTH = "oauth"
TOKEN = "token"
CREDENTIALS = "credentials"


class _Unclear(Exception):
    pass


def _typed_in_fields(field: FieldType) -> Iterator[FieldType]:
    """The fields a user types in for one connection field. Raises `_Unclear` when the shape has a choice."""
    if isinstance(field, SourceFieldSelectConfig):
        typed_in_options = [
            option for option in field.options if option.fields and option.value not in reference_option_values(field)
        ]
        if not any(option.fields for option in field.options):
            # A plain choice, such as a region. It is a typed-in field itself.
            yield field
        elif len(typed_in_options) == 1:
            for nested in typed_in_options[0].fields or []:
                yield from _typed_in_fields(nested)
        elif typed_in_options:
            # Several typed-in shapes, such as an API key or a key pair.
            raise _Unclear
        return
    yield field


def derive_credential_auth_type(source_config: SourceConfig) -> str:
    fields = list(source_config.fields)
    has_oauth = any(field_kind(field) == JobInputKind.REFERENCE or reference_option_values(field) for field in fields)
    try:
        typed_in = [
            leaf for field in fields if field_kind(field) == JobInputKind.CONNECTION for leaf in _typed_in_fields(field)
        ]
    except _Unclear:
        return CREDENTIALS
    if not typed_in:
        return OAUTH if has_oauth else CREDENTIALS
    if len(typed_in) == 1 and isinstance(typed_in[0], SourceFieldInputConfig) and typed_in[0].secret:
        return TOKEN
    return CREDENTIALS


def compute_credential_auth_types() -> dict[str, str]:
    """The default auth type of each credential kind, keyed by kind."""
    auth_types: dict[str, str] = {}
    for source in SourceRegistry.get_all_sources().values():
        kind = source.credential_kind
        if kind is not None:
            auth_types[kind] = source.credential_auth_type
    return dict(sorted(auth_types.items()))


def frozen_credential_auth_types(*, allow_changed: bool = False) -> dict[str, str]:
    """The committed default auth types plus the ones of new kinds. See `merge_append_only`."""
    return merge_append_only(
        CREDENTIAL_AUTH_TYPES,
        compute_credential_auth_types(),
        name="default auth types",
        allow_changed=allow_changed,
    )


def render_credential_auth_types(*, allow_changed: bool = False) -> str:
    lines = [
        '"""Generated by `python manage.py generate_source_field_classification`. Do not edit by hand.',
        "",
        "The default auth type of each warehouse source credential kind, keyed by kind. A row stores its auth",
        "type only when it is not the default, so a change to an existing value needs a data migration. See",
        "`sources/common/credential_auth_type.py` for the derivation. A kind in the integrations catalogue, such",
        "as `stripe`, keeps the default of the catalogue. The file is append-only: a removed kind keeps its",
        "entry.",
        '"""',
        "",
        "from collections.abc import Mapping",
        "",
        "CREDENTIAL_AUTH_TYPES: Mapping[str, str] = {",
    ]
    auth_types = frozen_credential_auth_types(allow_changed=allow_changed)
    lines += [f'    "{kind}": "{auth_type}",' for kind, auth_type in auth_types.items()]
    lines += ["}", ""]
    return "\n".join(lines)
