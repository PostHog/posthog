function meaningfulWords(text: string): string[] {
    return (
        text
            .toLowerCase()
            .match(/[a-z][a-z0-9]+/g)
            ?.filter((word) => word.length > 2 || word === 'ai') ?? []
    )
}

export function chatDictationPhrases(draftText = ''): string[] {
    const draftWords = new Set(meaningfulWords(draftText))
    if (draftWords.size === 0) return CHAT_DICTATION_PHRASES.slice(0, MAX_CONTEXTUAL_PHRASES)

    return CHAT_DICTATION_PHRASES.map((phrase) => ({
        phrase,
        score: meaningfulWords(phrase).filter((word) => draftWords.has(word)).length,
    }))
        .sort((left, right) => right.score - left.score)
        .slice(0, MAX_CONTEXTUAL_PHRASES)
        .map(({ phrase }) => phrase)
}
