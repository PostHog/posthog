export const mcpGatewaySettingsLogic = kea<mcpGatewaySettingsLogicType>([
    path(['products', 'mcp_store', 'frontend', 'settings', 'mcpGatewaySettingsLogic']),
    connect(() => ({
        values: [mcpGatewayLogic, ['config', 'configLoading', 'isAdmin']],
        actions: [
            mcpGatewayLogic,
            [
                'loadConfig',
                'loadConfigSuccess',
                'loadConfigFailure',
                'loadServers',
                'loadTemplates',
                'loadServiceAccounts',
                'loadRules',
                'refreshServersAfterConnection',
            ],
        ],
    })),
    actions({
        setTab: (tab: GatewayTab) => ({ tab }),
        syncTabFromUrl: (tab: string | null) => ({ tab }),
        resolveRequestedTab: true,
        _setTab: (tab: GatewayTab) => ({ tab }),
        handleOAuthCallback: (result: 'success' | 'error') => ({ result }),
        refreshGatewayData: true,
        openServer: (id: string, scope?: string) => ({ id, scope }),
        openAgent: (id: string) => ({ id }),
        openMember: (id: number) => ({ id }),
        closeDetail: (tab: GatewayTab) => ({ tab }),
        syncDetailFromUrl: (view: GatewaySettingsDetailView | null, id: string | null, scope: string | null) => ({
            view,
            id,
            scope,
        }),
    }),
    reducers({
        activeTab: [
            'servers' as GatewayTab,
            {
                _setTab: (_, { tab }) => tab,
                setTab: (_, { tab }) => tab,
                openServer: () => 'servers',
                openAgent: () => 'team',
                openMember: () => 'team',
                closeDetail: (_, { tab }) => tab,
            },
        ],
        requestedTab: [null as string | null, { syncTabFromUrl: (_, { tab }) => tab }],
        configInitialized: [
            false,
            {
                loadConfigSuccess: () => true,
                loadConfigFailure: () => true,
            },
        ],
        configLoadFailed: [
            false,
            {
                loadConfig: () => false,
                loadConfigSuccess: () => false,
                loadConfigFailure: () => true,
            },
        ],
        detailView: [
            null as GatewaySettingsDetailView | null,
            {
                syncDetailFromUrl: (_, { view }) => view,
                openServer: () => 'server',
                openAgent: () => 'agent',
                openMember: () => 'member',
                setTab: () => null,
                closeDetail: () => null,
            },
        ],
        detailId: [
            null as string | null,
            {
                syncDetailFromUrl: (_, { id }) => id,
                openServer: (_, { id }) => id,
                openAgent: (_, { id }) => id,
                openMember: (_, { id }) => String(id),
                setTab: () => null,
                closeDetail: () => null,
            },
        ],
        detailScope: [
            null as string | null,
            {
                syncDetailFromUrl: (_, { scope }) => scope,
                openServer: (_, { scope }) => scope ?? null,
                openAgent: () => null,
                openMember: () => null,
                setTab: () => null,
                closeDetail: () => null,
            },
        ],
    }),
    selectors({
        availableTabs: [(s) => [s.isAdmin], (isAdmin: boolean): GatewayTab[] => (isAdmin ? ADMIN_TABS : MEMBER_TABS)],
        permissionsInitialized: [
            (s) => [s.config, s.configInitialized],
            (config: TeamMCPGatewayConfigApi | null, configInitialized: boolean): boolean =>
                config !== null || configInitialized,
        ],
    }),
    listeners(({ actions, values }) => ({
        syncDetailFromUrl: () => {
            if (!values.detailView || !values.detailId) {
                return
            }
            const allowed = values.detailView === 'server' || values.isAdmin
            if (values.permissionsInitialized && !allowed) {
                router.actions.replace(
                    urls.settings('mcp-servers'),
                    searchParamsWithout(['id', 'scope', 'tab', 'view']),
                    router.values.hashParams
                )
            }
        },
        syncTabFromUrl: () => {
            if (values.permissionsInitialized) {
                actions.resolveRequestedTab()
            }
        },
        loadConfigSuccess: () => {
            actions.resolveRequestedTab()
            actions.syncDetailFromUrl(values.detailView, values.detailId, values.detailScope)
        },
        loadConfigFailure: () => {
            actions.resolveRequestedTab()
            actions.syncDetailFromUrl(values.detailView, values.detailId, values.detailScope)
        },
        resolveRequestedTab: () => {
            const requestedTab = isGatewayTab(values.requestedTab) ? values.requestedTab : 'servers'
            const nextTab = values.availableTabs.includes(requestedTab) ? requestedTab : 'servers'

            if (values.activeTab !== nextTab) {
                actions._setTab(nextTab)
            }

            if (values.requestedTab !== null && (nextTab === 'servers' || values.requestedTab !== nextTab)) {
                router.actions.replace(
                    router.values.location.pathname,
                    searchParamsWithout(['tab']),
                    router.values.hashParams
                )
            }
        },
        handleOAuthCallback: ({ result }) => {
            if (result === 'success') {
                lemonToast.success('Server connected')
                actions.refreshServersAfterConnection()
            } else {
                lemonToast.error('OAuth authorization failed. Try connecting the server again.')
                actions.loadServers()
            }
            actions.loadConfig()
            actions.loadTemplates()
            actions.loadServiceAccounts()
            actions.loadRules()
            router.actions.replace(
                router.values.location.pathname,
                searchParamsWithout(['oauth_complete', 'oauth_error']),
                router.values.hashParams
            )
        },
        refreshGatewayData: () => {
            actions.loadConfig()
            actions.loadServers()
            actions.loadTemplates()
            actions.loadServiceAccounts()
            actions.loadRules()
        },
    })),
    actionToUrl(({ values }) => ({
        setTab: ({ tab }) => {
            const nextTab = values.availableTabs.includes(tab) ? tab : 'servers'
            const searchParams = searchParamsWithout(['id', 'scope', 'tab', 'view'])

            return [
                urls.settings('mcp-servers'),
                nextTab === 'servers' ? searchParams : { ...searchParams, tab: nextTab },
                router.values.hashParams,
            ]
        },
        openServer: ({ id, scope }) => [
            urls.settings('mcp-servers'),
            {
                ...searchParamsWithout(['id', 'scope', 'tab', 'view']),
                view: 'server',
                id,
                ...(scope ? { scope } : {}),
            },
            router.values.hashParams,
        ],
        openAgent: ({ id }) => [
            urls.settings('mcp-servers'),
            { ...searchParamsWithout(['id', 'scope', 'tab', 'view']), tab: 'team', view: 'agent', id },
            router.values.hashParams,
        ],
        openMember: ({ id }) => [
            urls.settings('mcp-servers'),
            { ...searchParamsWithout(['id', 'scope', 'tab', 'view']), tab: 'team', view: 'member', id: String(id) },
            router.values.hashParams,
        ],
        closeDetail: ({ tab }) => [
            urls.settings('mcp-servers'),
            {
                ...searchParamsWithout(['id', 'scope', 'tab', 'view']),
                ...(tab === 'servers' ? {} : { tab }),
            },
            router.values.hashParams,
        ],
    })),
    urlToAction(({ actions }) => ({
        [urls.settings('mcp-servers')]: (_, searchParams) => {
            const tab = typeof searchParams?.tab === 'string' ? searchParams.tab : null
            actions.syncTabFromUrl(tab)
            const view = isDetailView(searchParams?.view) ? searchParams.view : null
            const id = stringSearchParam(searchParams?.id)
            const scope = stringSearchParam(searchParams?.scope)
            actions.syncDetailFromUrl(view, id, scope)

            const callbackResult = oauthCallbackResult(searchParams ?? {})
            if (callbackResult) {
                actions.handleOAuthCallback(callbackResult)
            }
        },
    })),
    afterMount(({ actions, cache, values }) => {
        const searchParams = router.values.searchParams
        actions.syncTabFromUrl(typeof searchParams.tab === 'string' ? searchParams.tab : null)
        actions.syncDetailFromUrl(
            isDetailView(searchParams.view) ? searchParams.view : null,
            stringSearchParam(searchParams.id),
            stringSearchParam(searchParams.scope)
        )
        if (values.config === null && !values.configLoading) {
            actions.loadConfig()
        }
        cache.disposables.add(
            () => {
                let lastRefreshedAt = 0
                const refreshWhenVisible = (): void => {
                    if (
                        document.visibilityState !== 'visible' ||
                        Date.now() - lastRefreshedAt < GATEWAY_REFRESH_THROTTLE_MS
                    ) {
                        return
                    }
                    lastRefreshedAt = Date.now()
                    actions.refreshGatewayData()
                }
                window.addEventListener('focus', refreshWhenVisible)
                document.addEventListener('visibilitychange', refreshWhenVisible)
                return () => {
                    window.removeEventListener('focus', refreshWhenVisible)
                    document.removeEventListener('visibilitychange', refreshWhenVisible)
                }
            },
            'gatewayReturnRefresh',
            { pauseOnPageHidden: false }
        )
    }),
])
