import { actionToUrl, router, urlToAction } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import { urls } from 'scenes/urls'

import { mcpGatewayLogic } from '../gateway/mcpGatewayLogic'
import { ADMIN_TABS, GatewayTab, MEMBER_TABS } from '../gateway/mcpGatewaySceneLogic'
import { TeamMCPGatewayConfigApi } from '../generated/api.schemas'

export type GatewaySettingsDetailView = 'agent' | 'member' | 'server'

// Returning to the tab fires both 'focus' and 'visibilitychange', so throttle to one refresh per return
const GATEWAY_REFRESH_THROTTLE_MS = 1000

function isGatewayTab(tab: string | null): tab is GatewayTab {
    return tab !== null && ADMIN_TABS.includes(tab as GatewayTab)
}

function isDetailView(view: unknown): view is GatewaySettingsDetailView {
    return view === 'server' || view === 'agent' || view === 'member'
}

function stringSearchParam(value: unknown): string | null {
    return typeof value === 'string' ? value : typeof value === 'number' ? String(value) : null
}

function oauthCallbackResult(searchParams: Record<string, unknown>): 'error' | 'success' | null {
    if (searchParams.oauth_complete === true || searchParams.oauth_complete === 'true') {
        return 'success'
    }
    return searchParams.oauth_error ? 'error' : null
}

function searchParamsWithout(keys: string[]): Record<string, unknown> {
    return Object.fromEntries(Object.entries(router.values.searchParams).filter(([key]) => !keys.includes(key)))
}

