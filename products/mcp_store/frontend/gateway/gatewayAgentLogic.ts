export type gatewayAgentLogicType = MakeLogicType<
    gatewayAgentLogicValues,
    gatewayAgentLogicActions,
    GatewayAgentLogicProps,
    gatewayAgentLogicMeta
>

export const gatewayAgentLogic = kea<gatewayAgentLogicType>([
    path((key) => ['products', 'mcp_store', 'frontend', 'gateway', 'gatewayAgentLogic', key]),
    props({} as GatewayAgentLogicProps),
    key((props) => props.id),

    connect(() => ({
        values: [
            mcpGatewayLogic,
            [
                'accountStatusLoadingIds',
                'agentServerAccessLoadingKeys',
                'currentUserId',
                'servers as allServers',
                'serversLoading as allServersLoading',
                'serviceAccounts',
                'serviceAccountsInitialized as accountInitialized',
                'serviceAccountsLoading as accountLoading',
            ],
        ],
        actions: [mcpGatewayLogic, ['setAgentServerAccess', 'toggleAccountStatus']],
    })),

    actions({
        showMoreRecentCalls: true,
    }),

    loaders(({ props }) => ({
        recentCalls: [
            [] as MCPAuditEventApi[],
            {
                loadRecentCalls: async () => {
                    const response = await mcpGatewayAuditList(currentProjectId(), {
                        actor_service_account_id: props.id,
                        limit: 50,
                    })
                    return response.results
                },
            },
        ],
    })),

    reducers({
        shownRecentCalls: [5, { showMoreRecentCalls: (shownRecentCalls) => shownRecentCalls + 10 }],
    }),

    selectors({
        account: [
            (s) => [s.serviceAccounts, (_, props) => props.id],
            (serviceAccounts: MCPServiceAccountApi[], id: string): MCPServiceAccountApi | null =>
                serviceAccounts.find((account) => account.id === id) ?? null,
        ],
        breadcrumbs: [
            (s) => [s.account],
            (account: MCPServiceAccountApi | null): Breadcrumb[] => [
                { key: 'mcp-gateway', name: 'MCP servers', path: urls.mcpGatewayTab('team') },
                { key: 'mcp-gateway-agent', name: account?.name ?? 'Agent' },
            ],
        ],
        sharedServerIds: [
            (s) => [s.account],
            (account: MCPServiceAccountApi | null): Set<string> => new Set(account?.server_ids ?? []),
        ],
        sharesByServerId: [
            (s) => [s.account, s.allServers, s.currentUserId],
            (
                account: MCPServiceAccountApi | null,
                allServers: MCPGatewayServerApi[],
                currentUserId: number | null
            ): Record<string, AgentServerShare> =>
                Object.fromEntries(
                    allServers.map((server) => [server.id, agentServerShare(account, server.id, currentUserId)])
                ),
        ],
        // Viewer's own share count. `sharedServerIds` spans every member's grants,
        // so it would overcount next to the personal share switches.
        sharedByYouCount: [
            (s) => [s.sharesByServerId],
            (sharesByServerId: Record<string, AgentServerShare>): number =>
                Object.values(sharesByServerId).filter((share) => share.sharedByYou).length,
        ],
        sharedServers: [
            (s) => [s.allServers, s.sharedServerIds],
            (allServers: MCPGatewayServerApi[], sharedServerIds: Set<string>): MCPGatewayServerApi[] =>
                allServers.filter((server) => sharedServerIds.has(server.id)),
        ],
        unsharedServers: [
            (s) => [s.allServers, s.sharedServerIds],
            (allServers: MCPGatewayServerApi[], sharedServerIds: Set<string>): MCPGatewayServerApi[] =>
                allServers.filter((server) => !sharedServerIds.has(server.id)),
        ],
        visibleRecentCalls: [
            (s) => [s.recentCalls, s.shownRecentCalls],
            (recentCalls: MCPAuditEventApi[], shownRecentCalls: number): MCPAuditEventApi[] =>
                recentCalls.slice(0, shownRecentCalls),
        ],
    }),

    afterMount(({ actions }) => {
        actions.loadRecentCalls()
    }),
])
