import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import { urls } from 'scenes/urls'

import { mcpGatewayLogic } from './mcpGatewayLogic'

export type GatewayTab = 'servers' | 'team' | 'settings' | 'audit'

export const ADMIN_TABS: GatewayTab[] = ['servers', 'team', 'settings', 'audit']
export const MEMBER_TABS: GatewayTab[] = ['servers', 'audit']

function searchParamsWithoutOAuth(searchParams: Record<string, unknown>): Record<string, unknown> {
    return Object.fromEntries(
        Object.entries(searchParams).filter(([key]) => key !== 'oauth_complete' && key !== 'oauth_error')
    )
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface mcpGatewaySceneLogicValues {
    isAdmin: boolean // mcpGatewayLogic
    activeTab: GatewayTab
    availableTabs: GatewayTab[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface mcpGatewaySceneLogicActions {
    refreshServersAfterConnection: () => {
        value: true
    } // mcpGatewayLogic
    _setTab: (tab: GatewayTab) => {
        tab: GatewayTab
    }
    setTab: (tab: GatewayTab) => {
        tab: GatewayTab
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface mcpGatewaySceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        availableTabs: (isAdmin: boolean) => GatewayTab[]
    }
}

export type mcpGatewaySceneLogicType = MakeLogicType<
    mcpGatewaySceneLogicValues,
    mcpGatewaySceneLogicActions,
    Record<string, any>,
    mcpGatewaySceneLogicMeta
>

/** URL-synced active tab (see data_warehouse SourceScene pattern: `setTab` writes
 * the URL, `_setTab` reacts to it without a feedback loop). */
export const mcpGatewaySceneLogic = kea<mcpGatewaySceneLogicType>([
    path(['products', 'mcp_store', 'frontend', 'gateway', 'mcpGatewaySceneLogic']),
    connect(() => ({
        values: [mcpGatewayLogic, ['isAdmin']],
        actions: [mcpGatewayLogic, ['refreshServersAfterConnection']],
    })),
    actions({
        setTab: (tab: GatewayTab) => ({ tab }),
        _setTab: (tab: GatewayTab) => ({ tab }),
    }),
    reducers({
        activeTab: ['servers' as GatewayTab, { setTab: (_, { tab }) => tab, _setTab: (_, { tab }) => tab }],
    }),
    selectors({
        availableTabs: [(s) => [s.isAdmin], (isAdmin: boolean): GatewayTab[] => (isAdmin ? ADMIN_TABS : MEMBER_TABS)],
    }),
    listeners(({ values }) => ({
        [mcpGatewayLogic.actionTypes.loadConfigSuccess]: ({ config }) => {
            if (!config.is_admin && !MEMBER_TABS.includes(values.activeTab)) {
                router.actions.replace(urls.mcpGateway())
            }
        },
        [mcpGatewayLogic.actionTypes.loadConfigFailure]: () => {
            if (!MEMBER_TABS.includes(values.activeTab)) {
                router.actions.replace(urls.mcpGateway())
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setTab: () => (values.activeTab === 'servers' ? urls.mcpGateway() : urls.mcpGatewayTab(values.activeTab)),
    })),
    urlToAction(({ actions, values }) => {
        const handleOAuthCallback = (searchParams: Record<string, unknown>): void => {
            if (searchParams.oauth_complete === true || searchParams.oauth_complete === 'true') {
                lemonToast.success('Server connected')
                actions.refreshServersAfterConnection()
                router.actions.replace(
                    router.values.location.pathname,
                    searchParamsWithoutOAuth(searchParams),
                    router.values.hashParams
                )
            } else if (searchParams.oauth_error) {
                lemonToast.error('OAuth authorization failed. Try connecting the server again.')
                router.actions.replace(
                    router.values.location.pathname,
                    searchParamsWithoutOAuth(searchParams),
                    router.values.hashParams
                )
            }
        }

        return {
            [urls.mcpGateway()]: (_, searchParams) => {
                handleOAuthCallback(searchParams ?? {})
                if (values.activeTab !== 'servers') {
                    actions._setTab('servers')
                }
            },
            [urls.mcpGatewayTab(':tab')]: ({ tab }, searchParams) => {
                handleOAuthCallback(searchParams ?? {})
                const next = (ADMIN_TABS.includes(tab as GatewayTab) ? tab : 'servers') as GatewayTab
                const config = mcpGatewayLogic.values.config
                if (config !== null && !config.is_admin && !MEMBER_TABS.includes(next)) {
                    router.actions.replace(urls.mcpGateway())
                    return
                }
                if (next !== values.activeTab) {
                    actions._setTab(next)
                }
            },
        }
    }),
])
