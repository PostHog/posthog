/** The staff-only view of the health checks: what each check read and why the panel shows what it shows. */
export const experimentHealthDebugLogic = kea<experimentHealthDebugLogicType>([
    props({} as ExperimentLogicProps),
    key((props) => props.experimentId ?? 'new'),
    path((key) => ['products', 'experiments', 'health', 'experimentHealthDebugLogic', key]),
    connect((props: ExperimentLogicProps) => ({
        values: [
            experimentLogic(props),
            [
                'experiment',
                'healthFindings',
                'browserExperimentWarning',
                'browserNoMetricsWarning',
                'exposures',
                'exposuresLoading',
                'exposureCriteria',
                'isExperimentDraft',
                'orderedPrimaryMetricsWithResults',
                'orderedSecondaryMetricsWithResults',
                'experimentLoadCount',
            ],
        ],
    })),
    selectors({
        pageMetricCounts: [
            (s) => [s.orderedPrimaryMetricsWithResults, s.orderedSecondaryMetricsWithResults],
            (primary: unknown[], secondary: unknown[]): HealthDebugInput['pageMetricCounts'] => ({
                primary: primary.length,
                secondary: secondary.length,
            }),
        ],
        healthDebugChecks: [
            (s) => [
                s.experiment,
                s.healthFindings,
                s.browserExperimentWarning,
                s.browserNoMetricsWarning,
                s.pageMetricCounts,
                s.isExperimentDraft,
                s.exposures,
                s.exposuresLoading,
                s.exposureCriteria,
            ],
            (
                experiment: Experiment,
                healthFindings: HealthPanelFinding[] | null,
                browserWarning: HealthDebugInput['browserWarning'],
                browserNoMetricsWarning: boolean,
                pageMetricCounts: HealthDebugInput['pageMetricCounts'],
                isExperimentDraft: boolean,
                exposures: HealthDebugInput['exposures'],
                exposuresLoading: boolean,
                exposureCriteria: ExperimentExposureCriteria | undefined
            ): HealthDebugCheck[] =>
                buildHealthDebugChecks({
                    health: experiment.health,
                    panelFindings: healthFindings,
                    browserWarning,
                    browserNoMetricsWarning,
                    pageMetricCounts,
                    isExperimentDraft,
                    hoursSinceStart: hoursSinceStart(experiment.start_date),
                    exposures,
                    exposuresLoading,
                    multipleVariantHandling: resolveMultipleVariantHandling(
                        exposureCriteria?.multiple_variant_handling
                    ),
                }),
        ],
        healthDebugFacts: [
            (s) => [s.experiment, s.healthFindings, s.pageMetricCounts, s.experimentLoadCount],
            (
                experiment: Experiment,
                healthFindings: HealthPanelFinding[] | null,
                pageMetricCounts: HealthDebugInput['pageMetricCounts'],
                experimentLoadCount: number
            ): HealthDebugFact[] => [
                { label: 'Server health', value: describeServerHealth(experiment.health) },
                { label: 'Health panel', value: describePanel(healthFindings) },
                {
                    label: 'Page load',
                    value: `${experimentLoadCount}. Each finding is reported as shown once per load.`,
                },
                ...buildHealthDebugFacts(experiment, pageMetricCounts),
            ],
        ],
    }),
])
