function errorDetail(error: unknown): string {
    const { detail } = (error ?? {}) as { detail?: string }
    return detail || 'The request failed. Reload the inputs, and check the server logs if it keeps failing.'
}

/** The staff-only view of the health checks: what each check concluded, and the inputs it read, by domain. */
export const experimentHealthDebugLogic = kea<experimentHealthDebugLogicType>([
    props({} as ExperimentLogicProps),
    key((props) => props.experimentId ?? 'new'),
    path((key) => ['products', 'experiments', 'health', 'debug', 'experimentHealthDebugLogic', key]),
    connect((props: ExperimentLogicProps) => ({
        values: [
            experimentLogic(props),
            [
                'experiment',
                'experimentHealth',
                'experimentHealthLoading',
                'healthFindings',
                'browserExperimentWarning',
                'browserNoMetricsWarning',
                'exposures',
                'exposuresLoading',
                'isExperimentDraft',
                'experimentLoadCount',
            ],
            projectLogic,
            ['currentProjectId'],
        ],
        actions: [experimentLogic(props), ['loadExperimentHealthSuccess']],
    })),
    actions({
        setActiveDomain: (domain: HealthDebugDomain) => ({ domain }),
        setHealthInputsError: (error: string | null) => ({ error }),
    }),
    loaders(({ actions, props, values }) => ({
        // The error is caught and shown in the panel, because the loader's failure path would also raise a toast for
        // the same message.
        healthInputs: [
            null as ExperimentHealthInputsApi | null,
            {
                loadHealthInputs: async () => {
                    if (typeof props.experimentId !== 'number' || values.currentProjectId === null) {
                        return null
                    }
                    actions.setHealthInputsError(null)
                    try {
                        return await experimentsHealthInputsRetrieve(
                            String(values.currentProjectId),
                            props.experimentId
                        )
                    } catch (error) {
                        actions.setHealthInputsError(errorDetail(error))
                        return null
                    }
                },
            },
        ],
    })),
    reducers({
        activeDomain: ['experiment' as HealthDebugDomain, { setActiveDomain: (_, { domain }) => domain }],
        healthInputsError: [null as string | null, { setHealthInputsError: (_, { error }) => error }],
    }),
    selectors({
        pageMetricCounts: [
            (s) => [s.experiment],
            (experiment: Experiment): PageMetricCounts => ({
                primary: getSectionMetricUuids(experiment, false).length,
                secondary: getSectionMetricUuids(experiment, true).length,
            }),
        ],
        healthInputsState: [
            (s) => [s.healthInputs, s.healthInputsLoading, s.healthInputsError],
            (inputs: ExperimentHealthInputsApi | null, loading: boolean, error: string | null): HealthInputsState => ({
                inputs,
                loading,
                error,
            }),
        ],
        healthDebugChecks: [
            (s) => [
                s.experimentHealth,
                s.browserExperimentWarning,
                s.browserNoMetricsWarning,
                s.isExperimentDraft,
                s.exposures,
                s.exposuresLoading,
                s.healthInputs,
                s.healthInputsLoading,
            ],
            (
                experimentHealth: ExperimentHealthApi | null,
                browserWarning: ExperimentWarning | null,
                browserNoMetricsWarning: boolean,
                isExperimentDraft: boolean,
                exposures: HealthDebugInput['exposures'],
                exposuresLoading: boolean,
                healthInputs: ExperimentHealthInputsApi | null,
                healthInputsLoading: boolean
            ): HealthDebugCheck[] =>
                buildHealthDebugChecks({
                    health: experimentHealth,
                    browserWarning,
                    browserNoMetricsWarning,
                    isExperimentDraft,
                    exposures,
                    exposuresLoading,
                    serverExposures: healthInputs?.exposures ?? null,
                    serverExposuresLoading: healthInputsLoading,
                }),
        ],
        healthDebugSummary: [
            (s) => [s.experimentHealth, s.healthFindings, s.healthDebugChecks, s.experimentLoadCount],
            (
                experimentHealth: ExperimentHealthApi | null,
                healthFindings: HealthPanelFinding[] | null,
                checks: HealthDebugCheck[],
                experimentLoadCount: number
            ): SetupFact[] => {
                const differing = checks
                    .filter(({ difference }) => difference === 'disagrees')
                    .map(({ check }) => check)
                return [
                    { label: 'Server health', value: describeServerHealth(experimentHealth) },
                    { label: 'Health panel', value: describePanel(healthFindings) },
                    {
                        label: 'Browser rules',
                        value: differing.length ? `Differ from the server on ${differing.join(', ')}` : 'Agree',
                        help: "The page's older rules for the flag state and the metrics. The page shows the server's findings when it has them.",
                    },
                    {
                        label: 'Page load',
                        value: String(experimentLoadCount),
                        help: 'Each finding is reported as shown once per load.',
                    },
                ]
            },
        ],
        experimentFacts: [
            (s) => [s.experiment, s.healthInputsState],
            (experiment: Experiment, state: HealthInputsState): SetupFact[] =>
                buildExperimentFacts(experiment, state, hoursSinceStart(experiment.start_date)),
        ],
        flagFacts: [
            (s) => [s.experiment, s.healthInputsState],
            (experiment: Experiment, state: HealthInputsState): SetupFact[] => buildFlagFacts(experiment, state),
        ],
        releaseConditions: [
            (s) => [s.healthInputs],
            (inputs: ExperimentHealthInputsApi | null): HealthDebugReleaseCondition[] => buildReleaseConditions(inputs),
        ],
        flagHistoryFacts: [
            (s) => [s.healthInputsState],
            (state: HealthInputsState): SetupFact[] => buildFlagHistoryFacts(state),
        ],
        flagChanges: [
            (s) => [s.healthInputs],
            (inputs: ExperimentHealthInputsApi | null): HealthDebugFlagChange[] => buildFlagChanges(inputs),
        ],
        trafficFacts: [
            (s) => [s.healthInputsState],
            (state: HealthInputsState): SetupFact[] => buildTrafficFacts(state),
        ],
        metricFacts: [
            (s) => [s.experiment, s.healthInputsState, s.pageMetricCounts],
            (experiment: Experiment, state: HealthInputsState, pageMetricCounts: PageMetricCounts): SetupFact[] =>
                buildMetricFacts(experiment, state, pageMetricCounts),
        ],
        exposureFacts: [
            (s) => [s.healthInputsState],
            (state: HealthInputsState): SetupFact[] => buildExposureFacts(state),
        ],
        healthDebugRawData: [
            (s) => [s.experimentHealth, s.healthFindings, s.healthInputs, s.exposures],
            (
                experimentHealth: ExperimentHealthApi | null,
                healthFindings: HealthPanelFinding[] | null,
                healthInputs: ExperimentHealthInputsApi | null,
                exposures: any
            ): Record<string, unknown> => ({
                health: experimentHealth,
                panelFindings: healthFindings,
                healthInputs,
                pageExposures: exposures
                    ? {
                          total_exposures: exposures.total_exposures,
                          sample_ratio_mismatch: exposures.sample_ratio_mismatch,
                          bias_risk: exposures.bias_risk,
                      }
                    : null,
            }),
        ],
    }),
    listeners(({ actions }) => ({
        // The inputs follow the findings, so that both describe the same save of the experiment.
        loadExperimentHealthSuccess: () => {
            actions.loadHealthInputs()
        },
    })),
    afterMount(({ actions, values }) => {
        // While the findings load, their success loads the inputs, so loading here too would ask twice.
        if (!values.experimentHealthLoading) {
            actions.loadHealthInputs()
        }
    }),
])
