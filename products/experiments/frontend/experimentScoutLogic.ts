export const experimentScoutLogic: LogicWrapper<experimentScoutLogicType> = kea<experimentScoutLogicType>([
    props({} as ExperimentScoutLogicProps),
    key((logicProps) => logicProps.experimentId),
    path((logicKey) => ['products', 'experiments', 'frontend', 'experimentScoutLogic', logicKey]),
    connect((logicProps: ExperimentScoutLogicProps) => ({
        actions: [
            experimentLogic({ experimentId: logicProps.experimentId }),
            ['launchExperimentSuccess'],
            integrationsLogic,
            ['loadIntegrations'],
        ],
        values: [
            aiConsentLogic,
            ['dataProcessingAccepted', 'dataProcessingApprovalDisabledReason'],
            integrationsLogic,
            ['githubIntegrations', 'integrations', 'integrationsLoading'],
            teamLogic,
            ['currentTeamId'],
        ],
    })),
    actions({
        checkSelfDrivingSetup: true,
        checkSelfDrivingSetupComplete: true,
        continueFromLaunch: true,
        openExperimentScoutSetup: true,
        openSelfDrivingSetup: true,
        closeExperimentScoutModal: true,
    }),
    loaders(({ values }) => ({
        experimentScoutSetupStatus: [
            null as ExperimentScoutSetupStatus | null,
            {
                loadExperimentScoutSetupStatus: async (): Promise<ExperimentScoutSetupStatus> =>
                    values.currentTeamId
                        ? loadExperimentScoutSetupStatus(values.currentTeamId)
                        : { enrolled: false, selfDrivingEnabled: false },
            },
        ],
    })),
    reducers({
        experimentScoutModalStep: [
            null as ExperimentScoutModalStep,
            {
                launchExperimentSuccess: () => 'launch-success',
                openSelfDrivingSetup: () => 'self-driving-setup',
                openExperimentScoutSetup: () => 'scout-setup',
                closeExperimentScoutModal: () => null,
            },
        ],
        checkingSelfDrivingSetup: [
            false,
            {
                checkSelfDrivingSetup: () => true,
                checkSelfDrivingSetupComplete: () => false,
            },
        ],
    }),
    selectors(({ props: logicProps }) => ({
        githubConnected: [
            (selectors) => [selectors.githubIntegrations],
            (integrations: IntegrationType[]) => integrations.length > 0,
        ],
        manualSetupReady: [
            (selectors) => [selectors.dataProcessingAccepted, selectors.githubConnected],
            (dataProcessingAccepted: boolean, githubConnected: boolean): boolean =>
                dataProcessingAccepted && githubConnected,
        ],
        manualSetupDisabledReason: [
            (selectors) => [
                selectors.dataProcessingAccepted,
                selectors.dataProcessingApprovalDisabledReason,
                selectors.githubConnected,
                selectors.integrations,
                selectors.integrationsLoading,
            ],
            (
                dataProcessingAccepted: boolean,
                dataProcessingApprovalDisabledReason: string | null,
                githubConnected: boolean,
                integrations: IntegrationType[] | null,
                integrationsLoading: boolean
            ): string | null => {
                if (!dataProcessingAccepted) {
                    return dataProcessingApprovalDisabledReason ?? 'Enable AI data processing to continue'
                }
                if (integrations === null || integrationsLoading) {
                    return 'Checking your GitHub connection'
                }
                if (!githubConnected) {
                    return 'Connect GitHub to continue'
                }
                return null
            },
        ],
        needsSelfDrivingSetup: [
            (selectors) => [
                selectors.experimentScoutSetupStatus,
                selectors.dataProcessingAccepted,
                selectors.githubConnected,
            ],
            (status: ExperimentScoutSetupStatus | null, dataProcessingAccepted: boolean, githubConnected: boolean) =>
                !status?.selfDrivingEnabled || !dataProcessingAccepted || !githubConnected,
        ],
        scoutInitialValues: [() => [], () => getExperimentScoutInitialValues(logicProps.experimentId)],
    })),
    listeners(({ actions, values }) => ({
        continueFromLaunch: () => {
            if (values.needsSelfDrivingSetup) {
                actions.openSelfDrivingSetup()
            } else {
                actions.openExperimentScoutSetup()
            }
        },
        checkSelfDrivingSetup: async () => {
            if (!values.currentTeamId) {
                lemonToast.error('Could not find this project. Refresh the page and try again.')
                actions.checkSelfDrivingSetupComplete()
                return
            }
            try {
                const [, , status] = await Promise.all([
                    integrationsLogic.asyncActions.loadIntegrations(),
                    organizationLogic.asyncActions.loadCurrentOrganization(),
                    loadExperimentScoutSetupStatus(values.currentTeamId),
                ])
                actions.loadExperimentScoutSetupStatusSuccess(status)

                if (
                    status.selfDrivingEnabled &&
                    aiConsentLogic.values.dataProcessingAccepted &&
                    integrationsLogic.values.githubIntegrations.length > 0
                ) {
                    actions.openExperimentScoutSetup()
                } else {
                    lemonToast.info('Self-driving setup is not complete yet. Finish setup, then check again.')
                }
            } catch {
                lemonToast.error('Could not check Self-driving setup. Please try again.')
            } finally {
                actions.checkSelfDrivingSetupComplete()
            }
        },
        closeExperimentScoutModal: () => {
            const createScout = router.values.searchParams.createScout
            if (createScout !== EXPERIMENT_SCOUT_QUERY_VALUE && createScout !== EXPERIMENT_SELF_DRIVING_QUERY_VALUE) {
                return
            }
            const {
                createScout: _createScout,
                integration_id: _integrationId,
                installation_id: _installationId,
                github_setup_error: _githubSetupError,
                error_message: _errorMessage,
                github_install_pending: _githubInstallPending,
                ...remainingSearchParams
            } = router.values.searchParams
            router.actions.replace(router.values.location.pathname, remainingSearchParams, router.values.hashParams)
        },
    })),
    events(({ actions }) => ({
        afterMount: () => {
            actions.loadExperimentScoutSetupStatus()
        },
    })),
    urlToAction(({ actions, props: logicProps, values }) => {
        const openFromGitHubSetup = ({ id }: { id?: string }, searchParams: Record<string, any>): void => {
            if (Number(id) !== logicProps.experimentId) {
                return
            }
            if (
                searchParams.createScout === EXPERIMENT_SELF_DRIVING_QUERY_VALUE &&
                values.experimentScoutModalStep !== 'self-driving-setup'
            ) {
                actions.openSelfDrivingSetup()
            } else if (
                searchParams.createScout === EXPERIMENT_SCOUT_QUERY_VALUE &&
                values.experimentScoutModalStep !== 'scout-setup'
            ) {
                actions.openExperimentScoutSetup()
            }
        }

        return {
            [urls.experiment(':id')]: openFromGitHubSetup,
            [urls.experiment(':id', ':formMode')]: openFromGitHubSetup,
        }
    }),
])
