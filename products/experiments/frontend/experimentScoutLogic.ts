export function isExperimentScoutFlowEnabled(featureFlags: FeatureFlagsSet): boolean {
    return (
        featureFlags[FEATURE_FLAGS.EXPERIMENT_LAUNCH_SCOUT_FLOW] === 'test' &&
        !!featureFlags[FEATURE_FLAGS.PRODUCT_AUTONOMY]
    )
}

export function getExperimentScoutInitialValues(experimentId: number): ScoutCreateInitialValues {
    return {
        name: `signals-scout-experiment-${experimentId}`,
        description: `Monitors experiment ${experimentId} for validity issues and meaningful changes.`,
        body: `# Monitor experiment ${experimentId}

Analyze PostHog experiment ID ${experimentId} on every run.

- Check exposure balance, sample ratio mismatch, contamination, stalled exposure, and changes to the linked feature flag.
- Look beyond the headline result for meaningful changes across variants, primary and secondary metrics, and useful segments.
- Identify tradeoffs, regressions, or data-quality problems that could change the decision about this experiment.
- Compare findings with prior scout runs, scratchpad memory, and existing inbox reports before creating anything new.

Do not report expected variance, low-volume day-one noise, or a finding already covered by an open report. Validate each finding with the experiment results and supporting data. Create or update an inbox report only when the finding is specific and actionable.`,
        config: {
            tags: ['experiments', `experiment-${experimentId}`],
        },
    }
}

async function loadExperimentScoutSetupStatus(teamId: number | string): Promise<ExperimentScoutSetupStatus> {
    const metadata: ScoutMetadataApi = await signalsScoutMetadataGet(String(teamId))
    if (!metadata.enrolled) {
        return { enrolled: false, selfDrivingEnabled: false }
    }

    const [scoutConfigsResult, sourceConfigsResult] = await Promise.allSettled([
        signalsScoutConfigList(String(teamId)),
        api.signalSourceConfigs.list(),
    ])
    const scoutConfigs = scoutConfigsResult.status === 'fulfilled' ? scoutConfigsResult.value : []
    const sourceConfigs: SignalSourceConfig[] =
        sourceConfigsResult.status === 'fulfilled' ? sourceConfigsResult.value.results : []

    return {
        enrolled: true,
        selfDrivingEnabled:
            scoutConfigs.some((config) => config.enabled) || sourceConfigs.some((config) => config.enabled),
    }
}

