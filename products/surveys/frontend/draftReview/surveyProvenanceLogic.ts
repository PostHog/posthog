import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { projectLogic } from 'scenes/projectLogic'
import { surveyLogic } from 'scenes/surveys/surveyLogic'

import { Survey } from '~/types'

import { surveysActivityRetrieve } from 'products/surveys/frontend/generated/api'
import type { ActivityLogEntryApi } from 'products/surveys/frontend/generated/api.schemas'

import { SurveyProvenance, getSurveyProvenance } from './surveyProvenance'

type SurveyActivity =
    | { status: 'loading' }
    | { status: 'loaded'; entries: ActivityLogEntryApi[] }
    | { status: 'unavailable' }

export interface SurveyProvenanceLogicProps {
    surveyId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface surveyProvenanceLogicValues {
    currentProjectId: number | null // projectLogic
    survey: Survey // surveyLogic
    activity: SurveyActivity
    activityLoading: boolean
    provenance: SurveyProvenance | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface surveyProvenanceLogicActions {
    loadSurveySuccess: (survey: Survey, payload?: any) => { survey: Survey; payload?: any } // surveyLogic
    loadActivity: () => any
    loadActivityFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadActivitySuccess: (activity: SurveyActivity, payload?: any) => { activity: SurveyActivity; payload?: any }
}

export type surveyProvenanceLogicType = MakeLogicType<
    surveyProvenanceLogicValues,
    surveyProvenanceLogicActions,
    SurveyProvenanceLogicProps
>

export const surveyProvenanceLogic = kea<surveyProvenanceLogicType>([
    props({} as SurveyProvenanceLogicProps),
    key((props) => props.surveyId),
    path((key) => ['products', 'surveys', 'draftReview', 'surveyProvenanceLogic', key]),
    connect((props: SurveyProvenanceLogicProps) => ({
        values: [projectLogic, ['currentProjectId'], surveyLogic({ id: props.surveyId }), ['survey']],
        actions: [surveyLogic({ id: props.surveyId }), ['loadSurveySuccess']],
    })),
    loaders(({ props, values }) => ({
        activity: [
            { status: 'loading' } as SurveyActivity,
            {
                // Provenance is secondary to the review, so a failed load falls back quietly instead of
                // reaching the loaders plugin, which shows an error toast.
                loadActivity: async (): Promise<SurveyActivity> => {
                    try {
                        const page = await surveysActivityRetrieve(String(values.currentProjectId), props.surveyId)
                        return { status: 'loaded', entries: page.results }
                    } catch {
                        return { status: 'unavailable' }
                    }
                },
            },
        ],
    })),
    selectors({
        provenance: [
            (s) => [s.survey, s.activity],
            (survey, activity): SurveyProvenance | null =>
                activity.status === 'loading'
                    ? null
                    : getSurveyProvenance(survey, activity.status === 'loaded' ? activity.entries : null),
        ],
    }),
    listeners(({ actions }) => ({
        // An edit, including one PostHog AI makes, reloads the survey and adds an activity entry.
        loadSurveySuccess: () => actions.loadActivity(),
    })),
    afterMount(({ actions }) => actions.loadActivity()),
])
