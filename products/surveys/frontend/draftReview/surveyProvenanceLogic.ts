// The endpoint returns 10 rows by default, newest first, so a draft with many edits pushes its `created` row
// off the first page. Pages are capped at 100 rows and the walk at 5 pages, which covers any realistic draft.
const ACTIVITY_PAGE_SIZE = 100
const MAX_ACTIVITY_PAGES = 5

async function fetchActivityUntilCreated(
    projectId: string,
    surveyId: string,
    breakpoint: () => void
): Promise<ActivityLogEntryApi[]> {
    const entries: ActivityLogEntryApi[] = []
    for (let page = 1; page <= MAX_ACTIVITY_PAGES; page++) {
        const response = await surveysActivityRetrieve(projectId, surveyId, { limit: ACTIVITY_PAGE_SIZE, page })
        breakpoint()
        entries.push(...response.results)
        if (!response.next || entries.some((entry) => entry.activity === 'created')) {
            break
        }
    }
    return entries
}

export const surveyProvenanceLogic = kea<surveyProvenanceLogicType>([
    props({} as SurveyProvenanceLogicProps),
    key((props) => props.surveyId),
    path((key) => ['products', 'surveys', 'draftReview', 'surveyProvenanceLogic', key]),
    connect((props: SurveyProvenanceLogicProps) => ({
        values: [projectLogic, ['currentProjectId'], surveyLogic({ id: props.surveyId }), ['survey']],
        actions: [surveyLogic({ id: props.surveyId }), ['loadSurveySuccess', 'updateSurveySuccess']],
    })),
    loaders(({ props, values }) => ({
        activity: [
            { status: 'loading' } as SurveyActivity,
            {
                // Provenance is secondary to the review, so a failed load falls back quietly instead of
                // reaching the loaders plugin, which shows an error toast.
                loadActivity: async (_: void, breakpoint): Promise<SurveyActivity> => {
                    try {
                        const entries = await fetchActivityUntilCreated(
                            String(values.currentProjectId),
                            props.surveyId,
                            breakpoint
                        )
                        return { status: 'loaded', entries }
                    } catch (error) {
                        // A newer request or an unmount cancels this one; only the latest load may write.
                        if (error instanceof Error && isBreakpoint(error)) {
                            throw error
                        }
                        return { status: 'unavailable' }
                    }
                },
            },
        ],
    })),
    selectors({
        provenance: [
            (s) => [s.survey, s.activity],
            (survey: Survey, activity: SurveyActivity): SurveyProvenance | null =>
                activity.status === 'loading'
                    ? null
                    : getSurveyProvenance(survey, activity.status === 'loaded' ? activity.entries : null),
        ],
    }),
    listeners(({ actions }) => ({
        // An edit adds an activity entry. A reload covers AI edits, and inline name and description edits
        // save without reloading the survey.
        loadSurveySuccess: () => actions.loadActivity(),
        updateSurveySuccess: () => actions.loadActivity(),
    })),
    afterMount(({ actions }) => actions.loadActivity()),
])
