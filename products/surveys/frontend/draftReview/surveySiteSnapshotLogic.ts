import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { projectLogic } from 'scenes/projectLogic'

import { getExportsContentRetrieveUrl } from 'products/exports/frontend/generated/api'
import { surveysSiteSnapshotRetrieve } from 'products/surveys/frontend/generated/api'
import type {
    SiteSnapshotApi,
    SurveysSiteSnapshotRetrieveDevice,
} from 'products/surveys/frontend/generated/api.schemas'

const POLL_INTERVAL_MS = 2000
const GIVE_UP_AFTER_MS = 60_000

export interface SurveySiteSnapshotLogicProps {
    surveyId: string
    device: SurveysSiteSnapshotRetrieveDevice
}

export interface ReadySiteSnapshot {
    imageUrl: string
    pageUrl: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface surveySiteSnapshotLogicValues {
    currentProjectId: number | null // projectLogic
    readySnapshot: ReadySiteSnapshot | null
    siteSnapshot: SiteSnapshotApi | null
    siteSnapshotLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface surveySiteSnapshotLogicActions {
    loadSiteSnapshot: () => any
    loadSiteSnapshotFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSiteSnapshotSuccess: (
        siteSnapshot: SiteSnapshotApi | null,
        payload?: any
    ) => {
        siteSnapshot: SiteSnapshotApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface surveySiteSnapshotLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        readySnapshot: (siteSnapshot: any, currentProjectId: any) => ReadySiteSnapshot | null
    }
}

export type surveySiteSnapshotLogicType = MakeLogicType<
    surveySiteSnapshotLogicValues,
    surveySiteSnapshotLogicActions,
    SurveySiteSnapshotLogicProps,
    surveySiteSnapshotLogicMeta
>

export const surveySiteSnapshotLogic = kea<surveySiteSnapshotLogicType>([
    props({} as SurveySiteSnapshotLogicProps),
    key((props) => `${props.surveyId}-${props.device}`),
    path((key) => ['products', 'surveys', 'draftReview', 'surveySiteSnapshotLogic', key]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    loaders(({ props, values }) => ({
        siteSnapshot: [
            null as SiteSnapshotApi | null,
            {
                loadSiteSnapshot: async (): Promise<SiteSnapshotApi | null> =>
                    await surveysSiteSnapshotRetrieve(String(values.currentProjectId), props.surveyId, {
                        device: props.device,
                    }),
            },
        ],
    })),
    selectors({
        readySnapshot: [
            (s) => [s.siteSnapshot, s.currentProjectId],
            (siteSnapshot, currentProjectId): ReadySiteSnapshot | null =>
                siteSnapshot?.status === 'ready' && siteSnapshot.exported_asset_id !== null
                    ? {
                          imageUrl: getExportsContentRetrieveUrl(
                              String(currentProjectId),
                              siteSnapshot.exported_asset_id
                          ),
                          pageUrl: siteSnapshot.page_url,
                      }
                    : null,
        ],
    }),
    listeners(({ actions, cache }) => ({
        loadSiteSnapshotSuccess: ({ siteSnapshot }) => {
            if (siteSnapshot?.status === 'rendering' && Date.now() - cache.startedAt < GIVE_UP_AFTER_MS) {
                cache.disposables.add(() => {
                    const id = setTimeout(actions.loadSiteSnapshot, POLL_INTERVAL_MS)
                    return () => clearTimeout(id)
                }, 'poll')
            }
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.startedAt = Date.now()
        actions.loadSiteSnapshot()
    }),
])
