export const MODELS_LIST_PAGE_SIZE = 10
const ALL = 'all'
const ATTENTION = 'attention'

export type HealthFilter = typeof ATTENTION | IssueKind | typeof ALL

export interface ModelRow extends AttentionSubject {
    view: DataWarehouseSavedQuerySummary
}

interface SubjectIndex {
    bySavedQueryId: Map<string, AttentionSubject>
    byViewName: Map<string, AttentionSubject>
    rank: Map<AttentionSubject, number>
}

function indexSubjects(subjects: AttentionSubject[]): SubjectIndex {
    const index: SubjectIndex = { bySavedQueryId: new Map(), byViewName: new Map(), rank: new Map() }
    subjects.forEach((subject, rank) => {
        index.rank.set(subject, rank)
        const savedQueryId = subject.node?.saved_query_id
        if (savedQueryId && !index.bySavedQueryId.has(savedQueryId)) {
            index.bySavedQueryId.set(savedQueryId, subject)
        }
        const [check] = subject.failingChecks
        if (!subject.node && check?.subject_type === 'view') {
            index.byViewName.set(check.subject_name, subject)
        }
    })
    return index
}

function buildModelRows(
    views: DataWarehouseSavedQuerySummary[],
    subjects: AttentionSubject[],
    nodes: DataModelingNode[]
): ModelRow[] {
    const index = indexSubjects(subjects)
    const nodeBySavedQueryId = new Map(
        nodes.flatMap((node) => (node.saved_query_id ? [[node.saved_query_id, node]] : []))
    )
    const ranked = views.map((view, position) => {
        const subject = index.bySavedQueryId.get(view.id) ?? index.byViewName.get(view.name)
        const row: ModelRow = subject
            ? { ...subject, view }
            : {
                  key: `view-${view.id}`,
                  node: nodeBySavedQueryId.get(view.id) ?? null,
                  materialization: null,
                  failingChecks: [],
                  view,
              }
        return { row, rank: subject ? index.rank.get(subject)! : Infinity, position }
    })
    return ranked.sort((a, b) => a.rank - b.rank || a.position - b.position).map(({ row }) => row)
}

export function rowNeedsAttention(row: AttentionSubject): boolean {
    return subjectIssueKinds(row).length > 0
}

function matchesHealthFilter(row: ModelRow, filter: HealthFilter): boolean {
    if (filter === ALL) {
        return true
    }
    if (filter === ATTENTION) {
        return rowNeedsAttention(row)
    }
    return subjectIssueKinds(row).includes(filter)
}

function countByHealth(rows: ModelRow[]): Record<HealthFilter, number> {
    const counts: Record<HealthFilter, number> = {
        attention: 0,
        suspended: 0,
        failed: 0,
        behind: 0,
        checks: 0,
        all: rows.length,
    }
    for (const row of rows) {
        const kinds = subjectIssueKinds(row)
        counts.attention += kinds.length > 0 ? 1 : 0
        for (const kind of kinds) {
            counts[kind] += 1
        }
    }
    return counts
}

