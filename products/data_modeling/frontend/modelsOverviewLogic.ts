export type modelsOverviewLogicType = MakeLogicType<
    modelsOverviewLogicValues,
    modelsOverviewLogicActions,
    Record<string, any>,
    modelsOverviewLogicMeta
>

export const modelsOverviewLogic = kea<modelsOverviewLogicType>([
    path(['products', 'data_modeling', 'frontend', 'modelsOverviewLogic']),
    connect(() => ({
        values: [
            modelsSceneLogic,
            [
                'nodes',
                'dataWarehouseSavedQueries',
                'attentionModels',
                'behindSchedule',
                'modelsResolved',
                'modelsFailed',
                'noModelsYet',
            ],
            dataQualityOverviewLogic,
            ['checks', 'failingCheckCount', 'checksTruncated', 'checksStatus', 'snapshotLoaded', 'overviewError'],
        ],
        actions: [
            modelsSceneLogic,
            ['loadNodes', 'loadDataWarehouseSavedQueries'],
            dataQualityOverviewLogic,
            ['loadOverview'],
        ],
    })),
    selectors({
        modelsKnown: [
            (s) => [s.modelsResolved, s.modelsFailed],
            (modelsResolved: boolean, modelsFailed: boolean): boolean => modelsResolved && !modelsFailed,
        ],
        modelsFirstLoading: [
            (s) => [s.modelsResolved, s.modelsFailed],
            (modelsResolved: boolean, modelsFailed: boolean): boolean => !modelsResolved && !modelsFailed,
        ],
        checksKnown: [
            (s) => [s.snapshotLoaded, s.overviewError],
            (snapshotLoaded: boolean, overviewError: string | null): boolean => snapshotLoaded && !overviewError,
        ],
        checksFirstLoading: [
            (s) => [s.snapshotLoaded, s.overviewError],
            (snapshotLoaded: boolean, overviewError: string | null): boolean => !snapshotLoaded && !overviewError,
        ],
        materializationIssues: [
            (s) => [s.attentionModels, s.behindSchedule],
            (attentionModels: AttentionModel[], behindSchedule: BehindScheduleModel[]): OverviewIssue[] => [
                ...attentionModels.map(
                    (attention): OverviewIssue => ({
                        kind: attention.problem === 'Suspended' ? 'suspended' : 'failed',
                        key: `model-${attention.node.id}`,
                        attention,
                    })
                ),
                ...behindSchedule.map(
                    (behind): OverviewIssue => ({ kind: 'behind', key: `behind-${behind.node.id}`, behind })
                ),
            ],
        ],
        checkIssues: [
            (s) => [s.checks],
            (checks: DataQualityOverviewCheckApi[]): OverviewIssue[] =>
                checks
                    .filter((check) => FAILING_CHECK_STATUSES.has(check.last_status ?? ''))
                    .map((check): OverviewIssue => ({ kind: 'check', key: `check-${check.id}`, check })),
        ],
        overviewStats: [
            (s) => [
                s.modelsKnown,
                s.checksKnown,
                s.dataWarehouseSavedQueries,
                s.nodes,
                s.materializationIssues,
                s.failingCheckCount,
                s.checksTruncated,
            ],
            (
                modelsKnown: boolean,
                checksKnown: boolean,
                savedQueries: DataWarehouseSavedQuerySummary[],
                nodes: DataModelingNode[],
                materializationIssues: OverviewIssue[],
                failingCheckCount: number,
                checksTruncated: boolean
            ): OverviewStats => ({
                models: modelsKnown ? savedQueries.length : null,
                materialized: modelsKnown ? materializedViewCount(nodes) : null,
                materializationIssues: modelsKnown ? materializationIssues.length : null,
                failingChecks: checksKnown ? failingCheckCount : null,
                failingChecksIsLowerBound: checksKnown && checksTruncated,
            }),
        ],
        statItems: [
            (s) => [s.overviewStats, s.attentionModels, s.modelsFirstLoading, s.checksFirstLoading],
            (
                overviewStats: OverviewStats,
                attentionModels: AttentionModel[],
                modelsFirstLoading: boolean,
                checksFirstLoading: boolean
            ): OverviewStatItem[] =>
                overviewStatItems({
                    stats: overviewStats,
                    brokenModelCount: attentionModels.length,
                    modelsFirstLoading,
                    checksFirstLoading,
                }),
        ],
        nothingToReport: [
            (s) => [s.modelsKnown, s.checksKnown, s.materializationIssues, s.checkIssues],
            (
                modelsKnown: boolean,
                checksKnown: boolean,
                materializationIssues: OverviewIssue[],
                checkIssues: OverviewIssue[]
            ): boolean => modelsKnown && checksKnown && materializationIssues.length === 0 && checkIssues.length === 0,
        ],
        showFirstView: [
            (s) => [s.nothingToReport, s.noModelsYet],
            (nothingToReport: boolean, noModelsYet: boolean): boolean => nothingToReport && noModelsYet,
        ],
    }),
])
