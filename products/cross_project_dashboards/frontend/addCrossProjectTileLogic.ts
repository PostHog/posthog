export type addCrossProjectTileLogicType = MakeLogicType<
    addCrossProjectTileLogicValues,
    addCrossProjectTileLogicActions,
    AddCrossProjectTileLogicProps,
    addCrossProjectTileLogicMeta
>

export const addCrossProjectTileLogic = kea<addCrossProjectTileLogicType>([
    path((key) => ['products', 'cross_project_dashboards', 'frontend', 'addCrossProjectTileLogic', key]),
    props({} as AddCrossProjectTileLogicProps),
    key((props) => props.dashboardId),
    actions({
        openModal: true,
        closeModal: true,
        setProjectId: (projectId: number | null) => ({ projectId }),
        setInsightId: (insightId: number | null) => ({ insightId }),
        addTile: true,
        addTileFailure: true,
    }),
    reducers({
        isOpen: [false, { openModal: () => true, closeModal: () => false }],
        projectId: [null as number | null, { setProjectId: (_, { projectId }) => projectId, closeModal: () => null }],
        insightId: [
            null as number | null,
            {
                setInsightId: (_, { insightId }) => insightId,
                setProjectId: () => null,
                closeModal: () => null,
            },
        ],
        isAdding: [false, { addTile: () => true, addTileFailure: () => false, closeModal: () => false }],
    }),
    loaders(({ values }) => ({
        insights: [
            [] as InsightOption[],
            {
                loadInsights: async () => {
                    if (!values.projectId) {
                        return []
                    }
                    const response = await api.get(
                        `api/projects/${values.projectId}/insights/?basic=true&limit=${INSIGHT_PAGE_SIZE}`
                    )
                    return (response.results ?? []).map((insight: any) => ({
                        id: insight.id,
                        name: insight.name || insight.derived_name || `Insight ${insight.id}`,
                    }))
                },
            },
        ],
    })),
    selectors({
        projectOptions: [
            () => [organizationLogic.selectors.currentOrganization],
            (organization: null | import('~/types').OrganizationType) =>
                (organization?.projects ?? []).map((project) => ({ value: project.id, label: project.name })),
        ],
        insightOptions: [
            (s) => [s.insights],
            (insights: InsightOption[]) => insights.map((insight) => ({ value: insight.id, label: insight.name })),
        ],
        canAdd: [
            (s) => [s.projectId, s.insightId],
            (projectId: number | null, insightId: number | null) => !!projectId && !!insightId,
        ],
    }),
    listeners(({ values, props, actions }) => ({
        setProjectId: () => {
            actions.loadInsights()
        },
        addTile: async () => {
            const organizationId = organizationLogic.values.currentOrganization?.id
            if (!organizationId || !values.projectId || !values.insightId) {
                actions.closeModal()
                return
            }
            try {
                await crossProjectDashboardsTilesCreate(organizationId, props.dashboardId, {
                    project_id: values.projectId,
                    insight_id: values.insightId,
                } as any)
                actions.closeModal()
                // findMounted, not a direct reference: referencing another logic's actions
                // mounts it and fires its afterMount.
                crossProjectDashboardLogic.findMounted({ id: props.dashboardId })?.actions.loadDashboard()
            } catch (error: any) {
                lemonToast.error(error?.detail || 'Could not add that insight. Try again.')
                actions.addTileFailure()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadInsights()
    }),
])
