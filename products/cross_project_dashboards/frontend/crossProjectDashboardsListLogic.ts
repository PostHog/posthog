import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { organizationLogic } from 'scenes/organizationLogic'

import {
    crossProjectDashboardsCreate,
    crossProjectDashboardsDestroy,
    crossProjectDashboardsList,
} from './generated/api'
import type { CrossProjectDashboardListItemApi } from './generated/api.schemas'
import { openDeleteCrossProjectDashboardDialog } from './openDeleteCrossProjectDashboardDialog'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface crossProjectDashboardsListLogicValues {
    dashboards: CrossProjectDashboardListItemApi[]
    dashboardsLoading: boolean
    isCreating: boolean
    isNewModalOpen: boolean
    newName: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface crossProjectDashboardsListLogicActions {
    closeNewModal: () => {
        value: true
    }
    createDashboard: () => {
        value: true
    }
    createDashboardFailure: () => {
        value: true
    }
    deleteDashboard: (dashboard: CrossProjectDashboardListItemApi) => {
        dashboard: CrossProjectDashboardListItemApi
    }
    loadDashboards: () => any
    loadDashboardsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadDashboardsSuccess: (
        dashboards: CrossProjectDashboardListItemApi[],
        payload?: any
    ) => {
        dashboards: CrossProjectDashboardListItemApi[]
        payload?: any
    }
    openNewModal: () => {
        value: true
    }
    setNewName: (name: string) => {
        name: string
    }
}

export type crossProjectDashboardsListLogicType = MakeLogicType<
    crossProjectDashboardsListLogicValues,
    crossProjectDashboardsListLogicActions
>

export const crossProjectDashboardsListLogic = kea<crossProjectDashboardsListLogicType>([
    path(['products', 'cross_project_dashboards', 'frontend', 'crossProjectDashboardsListLogic']),
    actions({
        openNewModal: true,
        closeNewModal: true,
        setNewName: (name: string) => ({ name }),
        createDashboard: true,
        createDashboardFailure: true,
        deleteDashboard: (dashboard: CrossProjectDashboardListItemApi) => ({ dashboard }),
    }),
    reducers({
        isNewModalOpen: [false, { openNewModal: () => true, closeNewModal: () => false }],
        newName: ['', { setNewName: (_, { name }) => name, closeNewModal: () => '' }],
        isCreating: [
            false,
            { createDashboard: () => true, createDashboardFailure: () => false, closeNewModal: () => false },
        ],
    }),
    loaders({
        dashboards: [
            [] as CrossProjectDashboardListItemApi[],
            {
                loadDashboards: async () => {
                    const organizationId = organizationLogic.values.currentOrganization?.id
                    if (!organizationId) {
                        return []
                    }
                    const response = await crossProjectDashboardsList(organizationId)
                    return response.results
                },
            },
        ],
    }),
    listeners(({ values, actions }) => ({
        createDashboard: async () => {
            const organizationId = organizationLogic.values.currentOrganization?.id
            if (!organizationId || !values.newName.trim()) {
                actions.closeNewModal()
                return
            }
            try {
                const created = await crossProjectDashboardsCreate(organizationId, {
                    name: values.newName.trim(),
                } as any)
                actions.closeNewModal()
                router.actions.push(`/cross-project-dashboards/${created.id}`)
            } catch (error: any) {
                lemonToast.error(error?.detail || 'Could not create that dashboard. Try again.')
                actions.createDashboardFailure()
            }
        },
        deleteDashboard: ({ dashboard }) => {
            const organizationId = organizationLogic.values.currentOrganization?.id
            if (!organizationId) {
                return
            }
            openDeleteCrossProjectDashboardDialog(dashboard.name, async () => {
                await crossProjectDashboardsDestroy(organizationId, dashboard.id)
                actions.loadDashboards()
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadDashboards()
    }),
])
