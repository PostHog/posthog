export const crossProjectDashboardLogic = kea<crossProjectDashboardLogicType>([
    path((key) => ['products', 'cross_project_dashboards', 'frontend', 'crossProjectDashboardLogic', key]),
    props({} as CrossProjectDashboardLogicProps),
    key((props) => props.id),
    actions({
        loadDashboard: true,
        removeTile: (tileId: string) => ({ tileId }),
        setDates: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setInterval: (interval: IntervalType | null) => ({ interval }),
        enterLayoutEdit: true,
        exitLayoutEdit: true,
        setPendingLayouts: (layouts: Partial<ResponsiveTileLayouts>) => ({ layouts }),
        saveLayout: true,
        saveLayoutStarted: true,
        saveLayoutFailed: true,
        cancelLayoutEdit: true,
        setTileOverride: (tileId: string, overrides: CrossProjectDashboardFilters) => ({ tileId, overrides }),
        setTileColor: (tileId: string, color: string | null) => ({ tileId, color }),
        setProperties: (properties: AnyPropertyFilter[]) => ({ properties }),
    }),
    reducers({
        layoutEditMode: [false, { enterLayoutEdit: () => true, exitLayoutEdit: () => false }],
        layoutSaving: [
            false,
            { saveLayoutStarted: () => true, saveLayoutFailed: () => false, exitLayoutEdit: () => false },
        ],
        pendingLayouts: [
            null as Partial<ResponsiveTileLayouts> | null,
            {
                setPendingLayouts: (_, { layouts }) => layouts,
                enterLayoutEdit: () => null,
                exitLayoutEdit: () => null,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        missingPropertyKeys: [
            {} as Record<number, string[]>,
            {
                checkPropertyKeys: async () => {
                    return await findMissingPropertyKeys(
                        values.projectIds,
                        propertyKeysIn(values.dashboardFilters.properties)
                    )
                },
            },
        ],
        dashboard: [
            null as CrossProjectDashboardApi | null,
            {
                loadDashboard: async () => {
                    const organizationId = organizationLogic.values.currentOrganization?.id
                    if (!organizationId) {
                        return null
                    }
                    return await crossProjectDashboardsRetrieve(organizationId, props.id)
                },
            },
        ],
    })),
    selectors({
        tiles: [(s) => [s.dashboard], (dashboard: CrossProjectDashboardApi | null) => dashboard?.tiles ?? []],
        projectIds: [
            (s) => [s.tiles],
            (tiles: CrossProjectDashboardTileApi[]) => Array.from(new Set(tiles.map((tile) => tile.project_id))),
        ],
        dashboardFilters: [
            (s) => [s.dashboard],
            (dashboard: CrossProjectDashboardApi | null) =>
                ((dashboard?.filters as CrossProjectDashboardFilters | undefined) ??
                    {}) as CrossProjectDashboardFilters,
        ],
        // Only projects the organization listing returns, so a project the reader cannot reach
        // has no entry and its tile stays unlabeled.
        tileProjects: [
            () => [organizationLogic.selectors.currentOrganization],
            (currentOrganization: { teams?: TeamBasicType[] } | null) =>
                Object.fromEntries(
                    (currentOrganization?.teams ?? []).map((team) => [
                        team.id,
                        { name: team.name, timezone: team.timezone },
                    ])
                ) as Record<number, CrossProjectTileProject>,
        ],
        timezonesDiverge: [
            (s) => [s.tiles, s.tileProjects],
            (tiles: readonly CrossProjectDashboardTileApi[], tileProjects: Record<number, CrossProjectTileProject>) => {
                const zones = new Set(tiles.map((tile) => tileProjects[tile.project_id]?.timezone).filter(Boolean))
                return zones.size > 1
            },
        ],
        savedLayouts: [(s) => [s.tiles], (tiles: readonly CrossProjectDashboardTileApi[]) => layoutsForTiles(tiles)],
        hasUnsavedLayoutChanges: [
            (s) => [s.layoutEditMode, s.savedLayouts, s.pendingLayouts],
            (
                layoutEditMode: boolean,
                savedLayouts: ResponsiveTileLayouts,
                pendingLayouts: Partial<ResponsiveTileLayouts> | null
            ) => layoutEditMode && layoutsDiffer(savedLayouts, pendingLayouts),
        ],
        // Keeps the grid controlled, so switching back to the saved layout on cancel moves the tiles back.
        gridLayouts: [
            (s) => [s.hasUnsavedLayoutChanges, s.pendingLayouts, s.savedLayouts],
            (
                hasUnsavedLayoutChanges: boolean,
                pendingLayouts: Partial<ResponsiveTileLayouts> | null,
                savedLayouts: ResponsiveTileLayouts
            ): Partial<ResponsiveTileLayouts> =>
                hasUnsavedLayoutChanges && pendingLayouts ? pendingLayouts : savedLayouts,
        ],
    }),
    listeners(({ props, actions, values }) => {
        // Saves send the whole filters object, so they run one at a time to never start from a stale copy.
        let filterSaves: Promise<boolean> = Promise.resolve(true)
        const saveFilters = (
            update: (filters: CrossProjectDashboardFilters) => void,
            errorMessage: string
        ): Promise<boolean> => {
            filterSaves = filterSaves.then(async () => {
                const organizationId = organizationLogic.values.currentOrganization?.id
                if (!organizationId) {
                    return false
                }
                const filters: CrossProjectDashboardFilters = { ...values.dashboardFilters }
                update(filters)
                try {
                    actions.loadDashboardSuccess(
                        await crossProjectDashboardsPartialUpdate(organizationId, props.id, { filters })
                    )
                    return true
                } catch (error: any) {
                    lemonToast.error(error?.detail || errorMessage)
                    actions.loadDashboard()
                    return false
                }
            })
            return filterSaves
        }

        const applySavedTiles = (saved: CrossProjectDashboardTileApi[]): void => {
            if (!values.dashboard) {
                return
            }
            const byId = new Map(saved.map((tile) => [tile.id, tile]))
            actions.loadDashboardSuccess({
                ...values.dashboard,
                tiles: values.dashboard.tiles.map((tile) => byId.get(tile.id) ?? tile),
            })
        }

        return {
            setDates: async ({ dateFrom, dateTo }) => {
                await saveFilters((filters) => {
                    // An unset bound is dropped, so the stored blob carries only the bounds actually chosen
                    // and each tile keeps its own insight's value for the other one.
                    dateFrom ? (filters.date_from = dateFrom) : delete filters.date_from
                    dateTo ? (filters.date_to = dateTo) : delete filters.date_to
                }, 'Could not apply that date range. Try again.')
            },
            setInterval: async ({ interval }) => {
                await saveFilters((filters) => {
                    interval ? (filters.interval = interval) : delete filters.interval
                }, 'Could not apply that interval. Try again.')
            },
            enterLayoutEdit: () => {
                lemonToast.info('Now editing the dashboard. Press E or click Save to persist changes.')
            },
            saveLayout: async () => {
                if (values.layoutSaving) {
                    return
                }
                const organizationId = organizationLogic.values.currentOrganization?.id
                if (!organizationId || !values.hasUnsavedLayoutChanges || !values.pendingLayouts) {
                    actions.exitLayoutEdit()
                    return
                }
                const updates = changedTileLayouts(values.tiles, values.pendingLayouts)
                actions.saveLayoutStarted()
                try {
                    const saved = await Promise.all(
                        updates.map((update) =>
                            crossProjectDashboardsTilesPartialUpdate(organizationId, props.id, update.tileId, {
                                layouts: update.layouts,
                            })
                        )
                    )
                    // A reload would unmount the grid and refetch every tile.
                    applySavedTiles(saved)
                    actions.exitLayoutEdit()
                    lemonToast.success('Dashboard saved')
                } catch (error: any) {
                    lemonToast.error(error?.detail || 'Could not save the layout. Try again.')
                    actions.saveLayoutFailed()
                }
            },
            cancelLayoutEdit: () => {
                const promptEnabled =
                    !!featureFlagLogic.values.featureFlags[FEATURE_FLAGS.DASHBOARD_LAYOUT_DISCARD_PROMPT]
                if (!promptEnabled || !values.hasUnsavedLayoutChanges) {
                    actions.exitLayoutEdit()
                    return
                }
                LemonDialog.open({
                    title: 'Discard unsaved changes?',
                    description:
                        'You have unsaved layout changes. If you discard now, the dashboard will revert to its last saved state.',
                    primaryButton: {
                        children: 'Discard changes',
                        status: 'danger',
                        onClick: () => actions.exitLayoutEdit(),
                        'data-attr': 'cross-project-dashboard-edit-mode-discard-confirm',
                    },
                    secondaryButton: { children: 'Keep editing' },
                })
            },
            setProperties: async ({ properties }) => {
                const saved = await saveFilters((filters) => {
                    properties.length > 0 ? (filters.properties = properties) : delete filters.properties
                }, 'Could not apply that filter. Try again.')
                if (saved) {
                    // Checked here rather than on open: the answer only changes when the filter does.
                    actions.checkPropertyKeys()
                }
            },
            setTileOverride: async ({ tileId, overrides }) => {
                const organizationId = organizationLogic.values.currentOrganization?.id
                if (!organizationId) {
                    return
                }
                try {
                    const saved = await crossProjectDashboardsTilesPartialUpdate(organizationId, props.id, tileId, {
                        filters_overrides: overrides,
                    })
                    applySavedTiles([saved])
                    lemonToast.success('Tile filters saved')
                } catch (error: any) {
                    lemonToast.error(error?.detail || 'Could not save the tile filters. Try again.')
                }
            },
            setTileColor: async ({ tileId, color }) => {
                const organizationId = organizationLogic.values.currentOrganization?.id
                if (!organizationId) {
                    return
                }
                try {
                    applySavedTiles([
                        await crossProjectDashboardsTilesPartialUpdate(organizationId, props.id, tileId, { color }),
                    ])
                } catch (error: any) {
                    lemonToast.error(error?.detail || 'Could not change the tile color. Try again.')
                }
            },
            removeTile: async ({ tileId }) => {
                const organizationId = organizationLogic.values.currentOrganization?.id
                if (!organizationId) {
                    return
                }
                try {
                    await crossProjectDashboardsTilesDestroy(organizationId, props.id, tileId)
                } catch (error: any) {
                    lemonToast.error(error?.detail || 'Could not remove that tile. Try again.')
                }
                actions.loadDashboard()
            },
        }
    }),
    beforeUnload(({ values, actions }) => ({
        enabled: (newLocation) => {
            if (!values.hasUnsavedLayoutChanges) {
                return false
            }
            // An in-page navigation, such as opening a side panel, keeps the edits.
            return !(newLocation && newLocation.pathname === router.values.location.pathname)
        },
        message: 'Leave dashboard?\nChanges you made to the layout will be discarded.',
        onConfirm: () => actions.exitLayoutEdit(),
    })),
    afterMount(({ actions }) => {
        actions.loadDashboard()
    }),
])
