export type biConnectionsLogicType = MakeLogicType<
    biConnectionsLogicValues,
    biConnectionsLogicActions,
    BIConnectionsLogicProps,
    biConnectionsLogicMeta
>

export const biConnectionsLogic: LogicWrapper<biConnectionsLogicType> = kea<biConnectionsLogicType>([
    props({} as BIConnectionsLogicProps),
    key((props) => props.tabId),
    path((key) => ['products', 'data_warehouse', 'frontend', 'bi', 'biConnectionsLogic', key]),
    connect((props: BIConnectionsLogicProps) => ({
        values: [
            biEditorLogic({ tabId: props.tabId }),
            ['config', 'dataPaneSearch', 'databaseConnectionId'],
            databaseTableListLogic,
            ['allTablesMap', 'tableFieldsStatus', 'databaseFieldsComplete'],
        ],
        actions: [
            biEditorLogic({ tabId: props.tabId }),
            ['setDataSource', 'resetConfig'],
            databaseTableListLogic,
            ['hydrateTableFields', 'hydrateTableFieldsSuccess'],
        ],
    })),
    actions({ toggleConnection: (id: string, tableName?: string) => ({ id, tableName }) }),
    reducers({
        expandedIds: [
            [] as string[],
            {
                toggleConnection: (state, { id }) =>
                    state.includes(id) ? state.filter((key) => key !== id) : [...state, id],
                setDataSource: () => [],
                resetConfig: () => [],
            },
        ],
    }),
    selectors({
        connections: [
            (s) => [
                s.config,
                s.allTablesMap,
                s.expandedIds,
                s.tableFieldsStatus,
                s.databaseFieldsComplete,
                s.databaseConnectionId,
            ],
            (
                config: BIConfig,
                tables: Record<string, DatabaseSchemaTable>,
                expanded: string[],
                status: TableFieldsStatus,
                complete: boolean,
                connectionId: string | null
            ): BIConnection[] =>
                config.source && (config.source.connectionId ?? null) === connectionId
                    ? buildBIConnections(config.source, tables, expanded, status, complete)
                    : [],
        ],
        filteredConnections: [
            (s) => [s.connections, s.dataPaneSearch],
            (connections: BIConnection[], search: string): BIConnection[] => filterBIConnections(connections, search),
        ],
    }),
    listeners(({ actions, values }) => ({
        hydrateTableFieldsSuccess: () => {
            const tables = getPendingBIConnectionTables(values.connections)
            if (tables.length) {
                actions.hydrateTableFields(tables)
            }
        },
        toggleConnection: ({ id, tableName }) => {
            if (tableName && values.expandedIds.includes(id)) {
                actions.hydrateTableFields([tableName])
            }
        },
    })),
])
