import {
    MakeLogicType,
    LogicWrapper,
    actions,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
    selectors,
} from 'kea'

import { biEditorLogic } from 'scenes/data-warehouse/editor/bi/biEditorLogic'
import { getBIDataSourceKey } from 'scenes/data-warehouse/editor/bi/biEditorTypes'
import { POSTHOG_WAREHOUSE } from 'scenes/data-warehouse/editor/connectionSelectorLogic'
import { queryDatabaseLogic } from 'scenes/data-warehouse/editor/sidebar/queryDatabaseLogic'

import type { TreeDataItem } from '../../../../frontend/src/lib/lemon-ui/LemonTree/LemonTree'
import type { BIConfig, BIDataSource } from '../../../../frontend/src/scenes/data-warehouse/editor/bi/biEditorTypes'
import type { ExternalDataSourceConnectionOptionApi } from '../../../warehouse_sources/frontend/generated/api.schemas'
import { buildBIDataSourceTree, getBIDataSourceFolderIds, searchBIDataSourceTree } from './biDataSourceTree'

export interface BIDataSourcePickerLogicProps {
    tabId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface biDataSourcePickerLogicValues {
    config: BIConfig // biEditorLogic
    databaseLoading: boolean // biEditorLogic
    selectableDataSources: BIDataSource[] // biEditorLogic
    connectionId: string | null // queryDatabaseLogic
    databaseLoadError: string | null // queryDatabaseLogic
    selectedDirectSource: ExternalDataSourceConnectionOptionApi | undefined // queryDatabaseLogic
    treeData: TreeDataItem[] // queryDatabaseLogic
    expandedIds: string[] | null
    filteredTree: TreeDataItem[]
    open: boolean
    search: string
    sourceTree: TreeDataItem[]
    visibleExpandedIds: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface biDataSourcePickerLogicActions {
    setDataSource: (source: BIDataSource) => {
        source: BIDataSource
    } // biEditorLogic
    refreshDatabaseSchema: () => {
        value: true
    } // queryDatabaseLogic
    selectSource: (id: string) => {
        id: string
    }
    setExpandedIds: (ids: string[]) => {
        ids: string[]
    }
    setOpen: (open: boolean) => {
        open: boolean
    }
    setSearch: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface biDataSourcePickerLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        sourceTree: (
            treeData: TreeDataItem[],
            selectableDataSources: BIDataSource[],
            connectionId: string | null,
            selectedDirectSource: ExternalDataSourceConnectionOptionApi | undefined
        ) => TreeDataItem[]
        filteredTree: (sourceTree: TreeDataItem[], search: string) => TreeDataItem[]
        visibleExpandedIds: (filteredTree: TreeDataItem[], search: string, expandedIds: string[] | null) => string[]
    }
}

export type biDataSourcePickerLogicType = MakeLogicType<
    biDataSourcePickerLogicValues,
    biDataSourcePickerLogicActions,
    BIDataSourcePickerLogicProps,
    biDataSourcePickerLogicMeta
>

export const biDataSourcePickerLogic: LogicWrapper<biDataSourcePickerLogicType> = kea<biDataSourcePickerLogicType>([
    props({} as BIDataSourcePickerLogicProps),
    key((props) => props.tabId),
    path((key) => ['products', 'data_warehouse', 'frontend', 'bi', 'biDataSourcePickerLogic', key]),
    connect((props: BIDataSourcePickerLogicProps) => ({
        values: [
            biEditorLogic({ tabId: props.tabId }),
            ['selectableDataSources', 'config', 'databaseLoading'],
            queryDatabaseLogic,
            ['treeData', 'connectionId', 'selectedDirectSource', 'databaseLoadError'],
        ],
        actions: [
            biEditorLogic({ tabId: props.tabId }),
            ['setDataSource'],
            queryDatabaseLogic,
            ['refreshDatabaseSchema'],
        ],
    })),
    actions({
        setOpen: (open: boolean) => ({ open }),
        setSearch: (search: string) => ({ search }),
        setExpandedIds: (ids: string[]) => ({ ids }),
        selectSource: (id: string) => ({ id }),
    }),
    reducers({
        open: [false, { setOpen: (_, { open }) => open }],
        search: ['', { setSearch: (_, { search }) => search, setOpen: () => '' }],
        expandedIds: [null as string[] | null, { setExpandedIds: (_, { ids }) => ids, setOpen: () => null }],
    }),
    selectors({
        sourceTree: [
            (s) => [s.treeData, s.selectableDataSources, s.connectionId, s.selectedDirectSource],
            (
                tree: TreeDataItem[],
                sources: BIDataSource[],
                connectionId: string | null,
                selectedDirectSource: ExternalDataSourceConnectionOptionApi | undefined
            ) =>
                buildBIDataSourceTree(
                    tree,
                    sources,
                    !!connectionId && connectionId !== POSTHOG_WAREHOUSE,
                    selectedDirectSource?.schema_name,
                    connectionId
                ),
        ],
        filteredTree: [
            (s) => [s.sourceTree, s.search],
            (tree: TreeDataItem[], search: string) => searchBIDataSourceTree(tree, search),
        ],
        visibleExpandedIds: [
            (s) => [s.filteredTree, s.search, s.expandedIds],
            (tree: TreeDataItem[], search: string, expandedIds: string[] | null): string[] =>
                search || expandedIds === null ? getBIDataSourceFolderIds(tree) : expandedIds,
        ],
    }),
    listeners(({ actions, values }) => ({
        selectSource: ({ id }) => {
            const source = values.selectableDataSources.find((candidate) => getBIDataSourceKey(candidate) === id)
            if (source) {
                actions.setDataSource(source)
                actions.setOpen(false)
            }
        },
    })),
])
