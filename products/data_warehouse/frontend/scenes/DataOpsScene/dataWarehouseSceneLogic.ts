import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import type { FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { urls } from 'scenes/urls'

import { SIDE_PANEL_CONTEXT_KEY, SidePanelSceneContext } from '~/layout/navigation-3000/sidepanel/types'

import type { WarehouseStatusResponseApi } from '../../generated/api.schemas'
import { dataOpsVariantFromFlags } from './dataOpsVariant'
import type { DataOpsVariant } from './dataOpsVariant'
import { warehouseProvisioningLogic } from './tabs/warehouseProvisioningLogic'

export enum DataWarehouseTab {
    OVERVIEW = 'overview',
    MONITORING = 'monitoring',
    SETTINGS = 'settings',
}

function isDataWarehouseTab(tab: unknown): tab is DataWarehouseTab {
    return typeof tab === 'string' && (Object.values(DataWarehouseTab) as string[]).includes(tab)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataWarehouseSceneLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    warehouseStatus: WarehouseStatusResponseApi | null // warehouseProvisioningLogic
    activeTab: DataWarehouseTab | null
    availableTabs: DataWarehouseTab[]
    dataOpsVariant: DataOpsVariant | null
    selectedTab: DataWarehouseTab | null
    sidePanelContext: SidePanelSceneContext
    warehouseReady: boolean
    warehouseStatusResolved: boolean
}

