import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import {
    dataWarehouseHoglakeCredentialsCreate,
    dataWarehouseHoglakeCredentialsDestroy,
    dataWarehouseHoglakeCredentialsRetrieve,
    dataWarehouseHoglakeCredentialsRotateCreate,
} from 'products/data_warehouse/frontend/generated/api'
import type {
    HoglakeCredentialScopeEnumApi,
    HoglakeCredentialIssuedApi,
    HoglakeCredentialListResponseApi,
} from 'products/data_warehouse/frontend/generated/api.schemas'

export type HoglakeCredentialScope = HoglakeCredentialScopeEnumApi

const currentProjectId = (): string => String(teamLogic.values.currentTeamId)

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface hoglakeCredentialsLogicValues {
    hoglakeCredentials: HoglakeCredentialListResponseApi | null
    hoglakeCredentialsLoading: boolean
    isSubmitting: boolean
    issuedCredential: HoglakeCredentialIssuedApi | null
    newCredentialName: string
    newCredentialScope: HoglakeCredentialScope
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface hoglakeCredentialsLogicActions {
    createCredential: (params: { name: string; scope: HoglakeCredentialScope }) => {
        name: string
        scope: HoglakeCredentialScopeEnumApi
    }
    loadHoglakeCredentials: () => any
    loadHoglakeCredentialsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadHoglakeCredentialsSuccess: (
        hoglakeCredentials: HoglakeCredentialListResponseApi | null,
        payload?: any
    ) => {
        hoglakeCredentials: HoglakeCredentialListResponseApi | null
        payload?: any
    }
    revokeCredential: (clientId: string) => {
        clientId: string
    }
    rotateCredential: (clientId: string) => {
        clientId: string
    }
    setIssuedCredential: (issued: HoglakeCredentialIssuedApi | null) => {
        issued: HoglakeCredentialIssuedApi | null
    }
    setNewCredentialName: (name: string) => {
        name: string
    }
    setNewCredentialScope: (scope: HoglakeCredentialScope) => {
        scope: HoglakeCredentialScopeEnumApi
    }
    submitComplete: () => {
        value: true
    }
}

export type hoglakeCredentialsLogicType = MakeLogicType<hoglakeCredentialsLogicValues, hoglakeCredentialsLogicActions>

function errorMessage(e: any): string {
    return e?.data?.error || e?.detail || e?.message || 'Unknown error'
}

export const hoglakeCredentialsLogic = kea<hoglakeCredentialsLogicType>([
    path(['scenes', 'data-warehouse', 'scene', 'hoglakeCredentialsLogic']),

    actions({
        createCredential: (params: { name: string; scope: HoglakeCredentialScope }) => params,
        rotateCredential: (clientId: string) => ({ clientId }),
        revokeCredential: (clientId: string) => ({ clientId }),
        submitComplete: true,
        setIssuedCredential: (issued: HoglakeCredentialIssuedApi | null) => ({ issued }),
        setNewCredentialName: (name: string) => ({ name }),
        setNewCredentialScope: (scope: HoglakeCredentialScope) => ({ scope }),
    }),

    loaders({
        hoglakeCredentials: [
            null as HoglakeCredentialListResponseApi | null,
            {
                loadHoglakeCredentials: async () => {
                    try {
                        return await dataWarehouseHoglakeCredentialsRetrieve(currentProjectId())
                    } catch (e: any) {
                        // 403: not an org admin, or the feature is off. 501: no hogtower
                        // control plane. Either way there is nothing to show.
                        if (e.status === 403 || e.status === 501) {
                            return null
                        }
                        throw e
                    }
                },
            },
        ],
    }),

    reducers({
        // The one response that carries a secret. Held only until the banner is closed.
        issuedCredential: [
            null as HoglakeCredentialIssuedApi | null,
            { setIssuedCredential: (_, { issued }) => issued },
        ],
        isSubmitting: [
            false,
            {
                createCredential: () => true,
                rotateCredential: () => true,
                revokeCredential: () => true,
                submitComplete: () => false,
            },
        ],
        newCredentialName: ['', { setNewCredentialName: (_, { name }) => name }],
        newCredentialScope: ['read' as HoglakeCredentialScope, { setNewCredentialScope: (_, { scope }) => scope }],
    }),

    listeners(({ actions }) => ({
        createCredential: async ({ name, scope }) => {
            try {
                const issued = await dataWarehouseHoglakeCredentialsCreate(currentProjectId(), { name, scope })
                actions.setIssuedCredential(issued)
                actions.setNewCredentialName('')
                posthog.capture('managed warehouse hoglake credential created', { scope })
                lemonToast.success('Hoglake credential created')
            } catch (e: any) {
                lemonToast.error(`Failed to create the credential: ${errorMessage(e)}`)
            }
            actions.submitComplete()
            actions.loadHoglakeCredentials()
        },
        rotateCredential: async ({ clientId }) => {
            try {
                const issued = await dataWarehouseHoglakeCredentialsRotateCreate(currentProjectId(), clientId)
                actions.setIssuedCredential(issued)
                posthog.capture('managed warehouse hoglake credential rotated')
                lemonToast.success('Secret rotated')
            } catch (e: any) {
                lemonToast.error(`Failed to rotate the secret: ${errorMessage(e)}`)
            }
            actions.submitComplete()
            actions.loadHoglakeCredentials()
        },
        revokeCredential: async ({ clientId }) => {
            try {
                await dataWarehouseHoglakeCredentialsDestroy(currentProjectId(), clientId)
                posthog.capture('managed warehouse hoglake credential revoked')
                lemonToast.success('Credential revoked')
            } catch (e: any) {
                lemonToast.error(`Failed to revoke the credential: ${errorMessage(e)}`)
            }
            actions.submitComplete()
            actions.loadHoglakeCredentials()
        },
    })),

    afterMount(({ actions }) => {
        actions.loadHoglakeCredentials()
    }),
])
