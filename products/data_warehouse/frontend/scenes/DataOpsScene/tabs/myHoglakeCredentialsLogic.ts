export type myHoglakeCredentialsLogicType = MakeLogicType<
    myHoglakeCredentialsLogicValues,
    myHoglakeCredentialsLogicActions,
    Record<string, any>,
    myHoglakeCredentialsLogicMeta
>

function errorMessage(e: any): string {
    return e?.data?.error || e?.detail || e?.message || 'Unknown error'
}

export const myHoglakeCredentialsLogic = kea<myHoglakeCredentialsLogicType>([
    path(['scenes', 'data-warehouse', 'scene', 'myHoglakeCredentialsLogic']),

    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),

    actions({
        createCredential: (params: { name: string; scope: HoglakeCredentialScope; teamIds: number[] }) => params,
        rotateCredential: (clientId: string) => ({ clientId }),
        revokeCredential: (clientId: string) => ({ clientId }),
        submitComplete: true,
        setIssuedCredential: (issued: HoglakeCredentialIssuedApi | null) => ({ issued }),
        setNewCredentialName: (name: string) => ({ name }),
        setNewCredentialScope: (scope: HoglakeCredentialScope) => ({ scope }),
        setSelectedTeamIds: (teamIds: number[]) => ({ teamIds }),
    }),

    loaders({
        myHoglakeCredentials: [
            null as MyHoglakeCredentialListResponseApi | null,
            {
                loadMyHoglakeCredentials: async () => {
                    try {
                        return await dataWarehouseMyHoglakeCredentialsRetrieve(currentProjectId())
                    } catch (e: any) {
                        // 403: no access to this project's warehouse objects. 501: no hogtower
                        // control plane, or personal credentials are off here. Nothing to show.
                        if (e.status === 403 || e.status === 501) {
                            return null
                        }
                        throw e
                    }
                },
            },
        ],
    }),

    reducers({
        // The one response that carries a secret. Held only until the banner is closed.
        issuedCredential: [
            null as HoglakeCredentialIssuedApi | null,
            { setIssuedCredential: (_, { issued }) => issued },
        ],
        isSubmitting: [
            false,
            {
                createCredential: () => true,
                rotateCredential: () => true,
                revokeCredential: () => true,
                submitComplete: () => false,
            },
        ],
        newCredentialName: ['', { setNewCredentialName: (_, { name }) => name }],
        newCredentialScope: ['read' as HoglakeCredentialScope, { setNewCredentialScope: (_, { scope }) => scope }],
        // null until the member picks: the current project, when they can use it.
        selectedTeamIds: [null as number[] | null, { setSelectedTeamIds: (_, { teamIds }) => teamIds }],
    }),

    selectors({
        projects: [
            (s) => [s.myHoglakeCredentials],
            (mine: MyHoglakeCredentialListResponseApi | null): HoglakeProjectApi[] => mine?.projects ?? [],
        ],
        effectiveTeamIds: [
            (s) => [s.selectedTeamIds, s.projects, s.currentTeamId],
            (selected: number[] | null, projects: HoglakeProjectApi[], currentTeamId: number | null): number[] => {
                const usable = new Set(projects.map((p) => p.id))
                if (selected !== null) {
                    return selected.filter((id) => usable.has(id))
                }
                return currentTeamId !== null && usable.has(currentTeamId) ? [currentTeamId] : []
            },
        ],
    }),

    listeners(({ actions }) => ({
        createCredential: async ({ name, scope, teamIds }) => {
            try {
                const issued = await dataWarehouseMyHoglakeCredentialsCreate(currentProjectId(), {
                    name,
                    scope,
                    team_ids: teamIds,
                })
                actions.setIssuedCredential(issued)
                actions.setNewCredentialName('')
                posthog.capture('managed warehouse personal hoglake credential created', {
                    scope,
                    project_count: teamIds.length,
                })
                lemonToast.success('Hoglake credential created')
            } catch (e: any) {
                lemonToast.error(`Failed to create the credential: ${errorMessage(e)}`)
            }
            actions.submitComplete()
            actions.loadMyHoglakeCredentials()
        },
        rotateCredential: async ({ clientId }) => {
            try {
                const issued = await dataWarehouseMyHoglakeCredentialsRotateCreate(currentProjectId(), clientId)
                actions.setIssuedCredential(issued)
                posthog.capture('managed warehouse personal hoglake credential rotated')
                lemonToast.success('Secret rotated')
            } catch (e: any) {
                lemonToast.error(`Failed to rotate the secret: ${errorMessage(e)}`)
            }
            actions.submitComplete()
            actions.loadMyHoglakeCredentials()
        },
        revokeCredential: async ({ clientId }) => {
            try {
                await dataWarehouseMyHoglakeCredentialsDestroy(currentProjectId(), clientId)
                posthog.capture('managed warehouse personal hoglake credential revoked')
                lemonToast.success('Credential revoked')
            } catch (e: any) {
                lemonToast.error(`Failed to revoke the credential: ${errorMessage(e)}`)
            }
            actions.submitComplete()
            actions.loadMyHoglakeCredentials()
        },
    })),

    afterMount(({ actions }) => {
        actions.loadMyHoglakeCredentials()
    }),
])
