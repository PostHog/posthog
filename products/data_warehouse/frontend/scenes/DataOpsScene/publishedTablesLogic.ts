export const publishedTablesLogic = kea<publishedTablesLogicType>([
    path(['products', 'dataWarehouse', 'scenes', 'DataOpsScene', 'publishedTablesLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        openPublishModal: true,
        closePublishModal: true,
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
    }),
    reducers({
        publishModalOpen: [
            false,
            {
                openPublishModal: () => true,
                closePublishModal: () => false,
            },
        ],
        searchTerm: [
            '',
            {
                setSearchTerm: (_, { searchTerm }) => searchTerm,
            },
        ],
        activeMutationId: [
            null as string | null,
            {
                republishTable: (_, id) => id,
                unpublishTable: (_, id) => id,
                republishTableSuccess: () => null,
                republishTableFailure: () => null,
                unpublishTableSuccess: () => null,
                unpublishTableFailure: () => null,
            },
        ],
        warehouseTablesError: [
            null as string | null,
            {
                loadWarehouseTables: () => null,
                loadWarehouseTablesSuccess: () => null,
                loadWarehouseTablesFailure: () => 'Could not load warehouse tables. Try again.',
            },
        ],
        publishedTablesError: [
            null as string | null,
            {
                loadPublishedTables: () => null,
                loadPublishedTablesSuccess: () => null,
                loadPublishedTablesFailure: () => 'Could not load published tables. Try again.',
            },
        ],
    }),
    loaders(({ values }) => ({
        publishedTables: [
            null as PublishedTableApi[] | null,
            {
                loadPublishedTables: async (): Promise<PublishedTableApi[]> => {
                    const response = await api.dataWarehouseManagedWarehousePublishedTablesRetrieve(
                        getProjectId(values.currentTeamId)
                    )
                    return response.results
                },
            },
        ],
        warehouseTables: [
            null as ModeledTableApi[] | null,
            {
                loadWarehouseTables: async (): Promise<ModeledTableApi[]> => {
                    const response = await api.dataWarehouseManagedWarehouseModeledTablesRetrieve(
                        getProjectId(values.currentTeamId)
                    )
                    return response.results
                },
            },
        ],
        republishedTable: [
            null as PublishedTableApi | null,
            {
                republishTable: async (id: string): Promise<PublishedTableApi> =>
                    await api.dataWarehouseManagedWarehouseRepublishTableCreate(getProjectId(values.currentTeamId), {
                        id,
                    }),
            },
        ],
        unpublishedTableId: [
            null as string | null,
            {
                unpublishTable: async (id: string): Promise<string> => {
                    await api.dataWarehouseManagedWarehousePublishedTableDestroy(getProjectId(values.currentTeamId), {
                        id,
                    })
                    return id
                },
            },
        ],
    })),
    forms(({ actions, values }) => ({
        publishTable: {
            defaults: {
                sourceSchemaName: '',
                sourceTableName: '',
                name: '',
            } as PublishTableFormValues,
            errors: ({ sourceSchemaName, sourceTableName, name }: PublishTableFormValues) => {
                const sourceTable = values.warehouseTables?.find(
                    (table) => table.schema_name === sourceSchemaName && table.table_name === sourceTableName
                )
                return {
                    sourceSchemaName: sourceSchemaName ? undefined : 'Select a schema',
                    sourceTableName: sourceTableName ? sourceTable?.disabled_reason || undefined : 'Select a table',
                    name:
                        name.trim() && !TABLE_NAME_PATTERN.test(name.trim())
                            ? 'Start with a letter or underscore, then use only letters, numbers, and underscores.'
                            : undefined,
                }
            },
            submit: async ({ sourceSchemaName, sourceTableName, name }: PublishTableFormValues): Promise<void> => {
                const sourceTable = values.warehouseTables?.find(
                    (table) => table.schema_name === sourceSchemaName && table.table_name === sourceTableName
                )
                if (!sourceTable) {
                    const error = new Error('The selected warehouse table is no longer available.')
                    lemonToast.error(error.message)
                    throw error
                }
                if (!sourceTable.publishable) {
                    const error = new Error(
                        sourceTable.disabled_reason || "PostHog manages this table, so you can't publish it."
                    )
                    lemonToast.error(error.message)
                    throw error
                }

                try {
                    await api.dataWarehouseManagedWarehousePublishTableCreate(getProjectId(values.currentTeamId), {
                        source_schema_name: sourceTable.schema_name,
                        source_table_name: sourceTable.table_name,
                        ...(name.trim() ? { name: name.trim() } : {}),
                    })
                    lemonToast.success('Table queued for publishing')
                    actions.closePublishModal()
                    actions.loadPublishedTables()
                } catch (error) {
                    lemonToast.error(getErrorMessage(error, 'Could not publish the table. Try again.'))
                    throw error
                }
            },
        },
    })),
    selectors({
        filteredPublishedTables: [
            (s) => [s.publishedTables, s.searchTerm],
            (publishedTables: PublishedTableApi[] | null, searchTerm: string): PublishedTableApi[] => {
                const normalizedSearchTerm = searchTerm.trim().toLowerCase()
                if (!normalizedSearchTerm) {
                    return publishedTables ?? []
                }
                return (publishedTables ?? []).filter((publication) =>
                    [publication.name, publication.source_schema_name, publication.source_table_name].some((value) =>
                        value.toLowerCase().includes(normalizedSearchTerm)
                    )
                )
            },
        ],
        hasActivePublications: [
            (s) => [s.publishedTables],
            (publishedTables: PublishedTableApi[] | null): boolean =>
                publishedTables?.some((publication) => ACTIVE_STATUSES.has(publication.status)) ?? false,
        ],
        warehouseSchemas: [
            (s) => [s.warehouseTables],
            (warehouseTables: ModeledTableApi[] | null): WarehouseSchemaOption[] => {
                const tablesBySchema = new Map<string, ModeledTableApi[]>()
                for (const table of warehouseTables ?? []) {
                    tablesBySchema.set(table.schema_name, [...(tablesBySchema.get(table.schema_name) ?? []), table])
                }
                return Array.from(tablesBySchema, ([name, tables]) => ({
                    name,
                    managed: tables.every((table) => !table.publishable),
                }))
            },
        ],
        selectedSchemaTables: [
            (s) => [s.warehouseTables, s.publishTable],
            (warehouseTables: ModeledTableApi[] | null, publishTable: PublishTableFormValues): ModeledTableApi[] =>
                (warehouseTables ?? []).filter((table) => table.schema_name === publishTable.sourceSchemaName),
        ],
        selectedWarehouseTable: [
            (s) => [s.selectedSchemaTables, s.publishTable],
            (selectedSchemaTables: ModeledTableApi[], publishTable: PublishTableFormValues): ModeledTableApi | null =>
                selectedSchemaTables.find((table) => table.table_name === publishTable.sourceTableName) ?? null,
        ],
        selectedSchemaDisabledReason: [
            (s) => [s.selectedSchemaTables],
            (selectedSchemaTables: ModeledTableApi[]): string | null => {
                if (selectedSchemaTables.length === 0 || selectedSchemaTables.some((table) => table.publishable)) {
                    return null
                }
                return selectedSchemaTables[0].disabled_reason
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const scheduleNextPoll = (): void => {
            cache.disposables.dispose('publishedTablesPoll')
            if (!values.hasActivePublications) {
                return
            }
            cache.disposables.add(() => {
                const timeoutId = window.setTimeout(() => actions.loadPublishedTables(), POLL_INTERVAL_MS)
                return () => window.clearTimeout(timeoutId)
            }, 'publishedTablesPoll')
        }

        return {
            openPublishModal: () => {
                actions.loadWarehouseTables()
            },
            closePublishModal: () => {
                actions.resetPublishTable()
            },
            setPublishTableValue: ({ name }) => {
                if (name === 'sourceSchemaName') {
                    actions.setPublishTableValue('sourceTableName', '')
                }
            },
            loadPublishedTablesSuccess: scheduleNextPoll,
            loadPublishedTablesFailure: scheduleNextPoll,
            republishTableSuccess: () => {
                lemonToast.success('Table queued for publishing')
                actions.loadPublishedTables()
            },
            republishTableFailure: ({ errorObject }) => {
                lemonToast.error(getErrorMessage(errorObject, 'Could not publish the table again. Try again.'))
            },
            unpublishTableSuccess: () => {
                lemonToast.success('Table unpublished')
                actions.loadPublishedTables()
            },
            unpublishTableFailure: ({ errorObject }) => {
                lemonToast.error(getErrorMessage(errorObject, 'Could not unpublish the table. Try again.'))
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadPublishedTables()
    }),
])
