export type warehousePipelineHealthLogicType = MakeLogicType<
    warehousePipelineHealthLogicValues,
    warehousePipelineHealthLogicActions,
    Record<string, any>,
    warehousePipelineHealthLogicMeta
>

export const warehousePipelineHealthLogic = kea<warehousePipelineHealthLogicType>([
    path([
        'products',
        'data_warehouse',
        'frontend',
        'scenes',
        'WarehousePipelineHealthScene',
        'warehousePipelineHealthLogic',
    ]),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeam', 'currentTeamId'],
            managedWarehouseDataStatusLogic,
            ['managedWarehouseDataStatus', 'managedWarehouseDataStatusLoading'],
        ],
        actions: [
            managedWarehouseDataStatusLogic,
            ['loadManagedWarehouseDataStatus', 'loadManagedWarehouseDataStatusSuccess'],
        ],
    })),
    actions({
        toggleSource: (sourceId: string) => ({ sourceId }),
        loadSourceSchemas: (sourceId: string) => ({ sourceId }),
        loadSourceSchemasSuccess: (sourceId: string, schemas: ManagedWarehouseSourceTableStatusApi[]) => ({
            sourceId,
            schemas,
        }),
        loadSourceSchemasFailure: (sourceId: string) => ({ sourceId }),
        retrySourceSchemas: (sourceId: string) => ({ sourceId }),
        linkClicked: (target: PipelineHealthLinkTarget) => ({ target }),
    }),
    reducers({
        expandedSourceId: [
            null as string | null,
            {
                toggleSource: (current, { sourceId }) => (current === sourceId ? null : sourceId),
            },
        ],
        schemasBySource: [
            {} as Record<string, ManagedWarehouseSourceTableStatusApi[]>,
            {
                loadSourceSchemasSuccess: (state, { sourceId, schemas }) => ({ ...state, [sourceId]: schemas }),
            },
        ],
        schemasLoading: [
            {} as Record<string, boolean>,
            {
                loadSourceSchemas: (state, { sourceId }) => ({ ...state, [sourceId]: true }),
                loadSourceSchemasSuccess: (state, { sourceId }) => ({ ...state, [sourceId]: false }),
                loadSourceSchemasFailure: (state, { sourceId }) => ({ ...state, [sourceId]: false }),
            },
        ],
        schemasFailed: [
            {} as Record<string, boolean>,
            {
                loadSourceSchemas: (state, { sourceId }) => ({ ...state, [sourceId]: false }),
                loadSourceSchemasFailure: (state, { sourceId }) => ({ ...state, [sourceId]: true }),
            },
        ],
    }),
    selectors({
        sources: [
            (s) => [s.managedWarehouseDataStatus],
            (status: ManagedWarehouseDataStatusResponseApi | null): ManagedWarehouseSourceSummaryApi[] =>
                status?.sources.sources ?? [],
        ],
        // The status logic keeps no failure flag: no data once loading has stopped means the load failed.
        statusFailed: [
            (s) => [s.managedWarehouseDataStatus, s.managedWarehouseDataStatusLoading],
            (status: ManagedWarehouseDataStatusResponseApi | null, loading: boolean): boolean =>
                status === null && !loading,
        ],
        expandedSource: [
            (s) => [s.sources, s.expandedSourceId],
            (
                sources: ManagedWarehouseSourceSummaryApi[],
                expandedSourceId: string | null
            ): ManagedWarehouseSourceSummaryApi | null =>
                sources.find((source) => source.source_id === expandedSourceId) ?? null,
        ],
        expandedSourceSchemas: [
            (s) => [s.schemasBySource, s.expandedSourceId],
            (
                schemasBySource: Record<string, ManagedWarehouseSourceTableStatusApi[]>,
                expandedSourceId: string | null
            ): ManagedWarehouseSourceTableStatusApi[] | null =>
                expandedSourceId ? (schemasBySource[expandedSourceId] ?? null) : null,
        ],
        ingestedEvent: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | TeamPublicType | null): boolean => !!currentTeam?.ingested_event,
        ],
    }),
    listeners(({ actions, values }) => ({
        toggleSource: ({ sourceId }) => {
            if (values.expandedSourceId !== sourceId) {
                return
            }
            const source = values.sources.find((candidate) => candidate.source_id === sourceId)
            posthog.capture('warehouse pipeline health source tables opened', {
                landing_state: source?.landing_state,
                source_type: source?.source_type,
            })
            if (!values.schemasBySource[sourceId] && !values.schemasLoading[sourceId]) {
                actions.loadSourceSchemas(sourceId)
            }
        },
        retrySourceSchemas: ({ sourceId }) => actions.loadSourceSchemas(sourceId),
        loadSourceSchemas: async ({ sourceId }) => {
            try {
                const response = await dataWarehouseManagedWarehouseSourceSchemasRetrieve(
                    String(values.currentTeamId),
                    { source_id: sourceId }
                )
                actions.loadSourceSchemasSuccess(sourceId, response.schemas)
            } catch {
                actions.loadSourceSchemasFailure(sourceId)
            }
        },
        // The source whose tables are open keeps current as the status polls. Its rows stay on screen while the reload runs.
        loadManagedWarehouseDataStatusSuccess: () => {
            if (values.expandedSourceId && !values.schemasLoading[values.expandedSourceId]) {
                actions.loadSourceSchemas(values.expandedSourceId)
            }
        },
        linkClicked: ({ target }) => {
            posthog.capture('warehouse pipeline health link clicked', { target })
        },
    })),
])
