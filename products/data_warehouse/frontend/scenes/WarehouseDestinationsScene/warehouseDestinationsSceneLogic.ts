export const warehouseDestinationsSceneLogic = kea<warehouseDestinationsSceneLogicType>([
    path([
        'products',
        'data_warehouse',
        'frontend',
        'scenes',
        'WarehouseDestinationsScene',
        'warehouseDestinationsSceneLogic',
    ]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        deleteDestination: (destination: ExternalDataDestinationApi) => ({ destination }),
        confirmDelete: (destination: ExternalDataDestinationApi) => ({ destination }),
        destinationCreated: (destination: ExternalDataDestinationApi) => ({ destination }),
        setSelectedDestinationId: (destinationId: string | null) => ({ destinationId }),
    }),
    loaders(({ values }) => ({
        destinations: [
            // Null, not an empty list: "this project has no destinations" is a verdict about a
            // loaded list, and the scene shows a different screen for it than for "not loaded yet".
            null as ExternalDataDestinationApi[] | null,
            {
                loadDestinations: async () => {
                    const response = await externalDataDestinationsList(String(values.currentTeamId))
                    return response.results ?? []
                },
            },
        ],
        hasSources: [
            // Null until loaded, so the page does not show "no sources" guidance while the check runs.
            null as boolean | null,
            {
                loadHasSources: async () => {
                    const response = await externalDataSourcesList(String(values.currentTeamId), { limit: 1 })
                    return (response.results ?? []).length > 0
                },
            },
        ],
    })),
    reducers({
        selectedDestinationId: [
            null as string | null,
            {
                setSelectedDestinationId: (_, { destinationId }) => destinationId,
            },
        ],
        loadError: [
            null as string | null,
            {
                loadDestinations: () => null,
                loadDestinationsSuccess: () => null,
                loadDestinationsFailure: (_, { error }) => error || 'Could not load destinations',
            },
        ],
        deletingId: [
            null as string | null,
            {
                confirmDelete: (_, { destination }) => destination.id,
                loadDestinationsSuccess: () => null,
                loadDestinationsFailure: () => null,
            },
        ],
    }),
    selectors({
        selectedDestination: [
            (s) => [s.destinations, s.selectedDestinationId],
            (
                destinations: ExternalDataDestinationApi[] | null,
                selectedDestinationId: string | null
            ): ExternalDataDestinationApi | null =>
                destinations?.find((destination) => destination.id === selectedDestinationId) ?? null,
        ],
    }),
    listeners(({ actions, values }) => ({
        deleteDestination: ({ destination }) => {
            LemonDialog.open({
                title: 'Delete this destination?',
                description: `Deleting ${destination.name} detaches it from every source and table that syncs to it. Those tables keep syncing to their other destinations. Runs already in flight finish where they started.`,
                primaryButton: {
                    children: 'Delete destination',
                    status: 'danger',
                    onClick: () => actions.confirmDelete(destination),
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        destinationCreated: () => {
            // A destination receives nothing until a source turns it on, so the toast points at that step.
            const hasSources = values.hasSources !== false
            lemonToast.success('Destination added. Turn it on for a source to start sending data to it.', {
                button: {
                    label: hasSources ? 'Go to sources' : 'Add a source',
                    action: () => router.actions.push(hasSources ? urls.sources() : urls.dataWarehouseSourceNew()),
                    dataAttr: 'warehouse-destinations-created-next-step',
                },
            })
        },
        confirmDelete: async ({ destination }) => {
            try {
                await externalDataDestinationsDestroy(String(values.currentTeamId), destination.id)
            } catch (error: any) {
                lemonToast.error(error?.detail || 'Could not delete this destination')
                actions.loadDestinations()
                return
            }
            lemonToast.success(`${destination.name} deleted`)
            if (values.selectedDestinationId === destination.id) {
                router.actions.push(urls.warehouseDestinations())
            }
            actions.loadDestinations()
        },
    })),
    // Emails, alerts and in-app links point at `?destination=<id>`, so that search param opens the destination.
    urlToAction(({ actions, values }) => ({
        [urls.warehouseDestinations()]: (_, searchParams) => {
            const destinationId = typeof searchParams.destination === 'string' ? searchParams.destination : null
            if (destinationId !== values.selectedDestinationId) {
                actions.setSelectedDestinationId(destinationId)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadDestinations()
        actions.loadHasSources()
    }),
])
