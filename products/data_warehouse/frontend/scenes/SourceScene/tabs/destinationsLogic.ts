// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface destinationsLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        hasUnsavedChanges: (attachedDestinationIds: string[], savedDestinationIds: string[]) => boolean
        canSave: (attachedDestinationIds: string[], hasUnsavedChanges: boolean) => boolean
    }
}

export type destinationsLogicType = MakeLogicType<
    destinationsLogicValues,
    destinationsLogicActions,
    DestinationsLogicProps,
    destinationsLogicMeta
>

export const destinationsLogic = kea<destinationsLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'scenes', 'SourceScene', 'tabs', 'destinationsLogic']),
    props({} as DestinationsLogicProps),
    key((props) => props.sourceId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        setAttached: (destinationIds: string[]) => ({ destinationIds }),
        toggleDestination: (destinationId: string) => ({ destinationId }),
        save: true,
    }),
    loaders(({ values, props }) => ({
        destinations: [
            [] as ExternalDataDestinationApi[],
            {
                loadDestinations: async () => {
                    const response = await externalDataDestinationsList(String(values.currentTeamId))
                    return response.results ?? []
                },
            },
        ],
        savedDestinationIds: [
            [] as string[],
            {
                loadAttached: async () => {
                    const response = await externalDataSourcesDestinationsRetrieve(
                        String(values.currentTeamId),
                        props.sourceId
                    )
                    return response.destination_ids ?? []
                },
                saveAttached: async (destinationIds: string[]) => {
                    const response = await externalDataSourcesDestinationsPartialUpdate(
                        String(values.currentTeamId),
                        props.sourceId,
                        { destination_ids: destinationIds }
                    )
                    return response.destination_ids ?? []
                },
            },
        ],
    })),
    reducers({
        attachedDestinationIds: [
            [] as string[],
            {
                setAttached: (_, { destinationIds }) => destinationIds,
                toggleDestination: (state, { destinationId }) =>
                    state.includes(destinationId)
                        ? state.filter((id) => id !== destinationId)
                        : [...state, destinationId],
                loadAttachedSuccess: (_, { savedDestinationIds }) => savedDestinationIds,
                saveAttachedSuccess: (_, { savedDestinationIds }) => savedDestinationIds,
            },
        ],
    }),
    selectors({
        hasUnsavedChanges: [
            (s) => [s.attachedDestinationIds, s.savedDestinationIds],
            (attached: string[], saved: string[]): boolean =>
                attached.length !== saved.length || attached.some((id: string) => !saved.includes(id)),
        ],
        // An empty set is rejected by the API: clearing every destination reads as "sync
        // nowhere", which is what turning syncing off is for. Say so before the request fails.
        canSave: [
            (s) => [s.attachedDestinationIds, s.hasUnsavedChanges],
            (attached: string[], hasUnsavedChanges: boolean): boolean => hasUnsavedChanges && attached.length > 0,
        ],
    }),
    listeners(({ values, actions }) => ({
        save: async () => {
            actions.saveAttached(values.attachedDestinationIds)
        },
        saveAttachedSuccess: () => {
            lemonToast.success('Destinations updated')
        },
        saveAttachedFailure: ({ error }) => {
            lemonToast.error(error || 'Could not update destinations')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadDestinations()
        actions.loadAttached()
    }),
])
