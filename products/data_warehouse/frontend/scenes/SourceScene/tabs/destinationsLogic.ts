export const destinationsLogic = kea<destinationsLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'scenes', 'SourceScene', 'tabs', 'destinationsLogic']),
    props({} as DestinationsLogicProps),
    key((props) => props.sourceId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        setAttached: (destinationIds: string[]) => ({ destinationIds }),
        toggleDestination: (destinationId: string) => ({ destinationId }),
        save: true,
        resyncAfterAdding: true,
    }),
    loaders(({ values, props }) => ({
        destinations: [
            [] as ExternalDataDestinationApi[],
            {
                loadDestinations: async () => {
                    const response = await externalDataDestinationsList(String(values.currentTeamId))
                    return response.results ?? []
                },
            },
        ],
        sourceSchemas: [
            [] as ExternalDataSourceSchema[],
            {
                loadSourceSchemas: async () => {
                    const source = await externalDataSourcesRetrieve(String(values.currentTeamId), props.sourceId)
                    // The generated shape for an embedded schema is an untyped map; the app-level
                    // type is what every other warehouse surface reads it as.
                    return (source.schemas ?? []) as unknown as ExternalDataSourceSchema[]
                },
            },
        ],
        savedDestinationIds: [
            [] as string[],
            {
                loadAttached: async () => {
                    const response = await externalDataSourcesDestinationsRetrieve(
                        String(values.currentTeamId),
                        props.sourceId
                    )
                    return response.destination_ids ?? []
                },
                saveAttached: async (destinationIds: string[]) => {
                    const response = await externalDataSourcesDestinationsPartialUpdate(
                        String(values.currentTeamId),
                        props.sourceId,
                        { destination_ids: destinationIds }
                    )
                    return response.destination_ids ?? []
                },
            },
        ],
    })),
    reducers({
        attachedDestinationIds: [
            [] as string[],
            {
                setAttached: (_, { destinationIds }) => destinationIds,
                toggleDestination: (state, { destinationId }) =>
                    state.includes(destinationId)
                        ? state.filter((id) => id !== destinationId)
                        : [...state, destinationId],
                loadAttachedSuccess: (_, { savedDestinationIds }) => savedDestinationIds,
                saveAttachedSuccess: (_, { savedDestinationIds }) => savedDestinationIds,
            },
        ],
    }),
    selectors({
        hasUnsavedChanges: [
            (s) => [s.attachedDestinationIds, s.savedDestinationIds],
            (attached: string[], saved: string[]): boolean =>
                attached.length !== saved.length || attached.some((id: string) => !saved.includes(id)),
        ],
        canSave: [
            (s) => [s.attachedDestinationIds, s.hasUnsavedChanges],
            (attached: string[], hasUnsavedChanges: boolean): boolean => hasUnsavedChanges && attached.length > 0,
        ],
        // A destination added now holds none of the history already synced, so these are the ones
        // that make a resync necessary. Removing one never does.
        addedDestinationIds: [
            (s) => [s.attachedDestinationIds, s.savedDestinationIds],
            (attached: string[], saved: string[]): string[] => attached.filter((id) => !saved.includes(id)),
        ],
        syncedSchemas: [
            (s) => [s.sourceSchemas],
            (schemas: ExternalDataSourceSchema[]): ExternalDataSourceSchema[] =>
                schemas.filter((schema) => schema.should_sync && !!schema.sync_type),
        ],
    }),
    listeners(({ values, actions, asyncActions }) => ({
        save: async () => {
            const added = values.addedDestinationIds
            const tables = values.syncedSchemas

            if (added.length === 0 || tables.length === 0) {
                actions.saveAttached(values.attachedDestinationIds)
                return
            }

            const addedNames = values.destinations
                .filter((destination) => added.includes(destination.id))
                .map((destination) => destination.name)
                .join(', ')

            LemonDialog.open({
                title: 'Resync to fill in the history?',
                description: `${addedNames} holds none of the data you have already synced. Saving resyncs ${pluralize(
                    tables.length,
                    'table',
                    'tables'
                )} from scratch so it gets the full history. Every table is read again from the source, and rows bill once per destination, so this bills for every destination on this source, not just the new one.`,
                primaryButton: {
                    children: 'Save and resync',
                    onClick: () => actions.resyncAfterAdding(),
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        // The save has to land before the resync: a resync against the old destination set would
        // re-import every table without the destination the user just agreed to pay for.
        resyncAfterAdding: async () => {
            const tables = values.syncedSchemas
            await asyncActions.saveAttached(values.attachedDestinationIds)

            const results = await Promise.allSettled(
                tables.map((schema) => externalDataSchemasResyncCreate(String(values.currentTeamId), schema.id, {}))
            )
            const failed = results.filter((result) => result.status === 'rejected').length
            if (failed > 0) {
                lemonToast.error(`Could not start a resync for ${pluralize(failed, 'table', 'tables')}`)
                return
            }
            lemonToast.success(`Resyncing ${pluralize(tables.length, 'table', 'tables')}`)
        },
        saveAttachedSuccess: () => {
            lemonToast.success('Destinations updated')
        },
        saveAttachedFailure: ({ error }) => {
            lemonToast.error(error || 'Could not update destinations')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadDestinations()
        actions.loadAttached()
        actions.loadSourceSchemas()
    }),
])
