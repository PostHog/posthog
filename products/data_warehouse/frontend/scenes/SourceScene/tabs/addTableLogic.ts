export const addTableLogic = kea<addTableLogicType>([
    props({} as AddTableLogicProps),
    key(({ sourceId }) => sourceId),
    path((key) => ['products', 'dataWarehouse', 'addTableLogic', key]),
    actions({
        openAddTable: true,
        closeAddTable: true,
        editName: (name: string) => ({ name }),
    }),
    reducers({
        isAddTableOpen: [
            false,
            {
                openAddTable: () => true,
                closeAddTable: () => false,
            },
        ],
        nameEdited: [
            false,
            {
                editName: () => true,
                openAddTable: () => false,
                closeAddTable: () => false,
            },
        ],
    }),
    forms(({ actions, props }) => ({
        addTable: {
            defaults: { ...DEFAULT_ADD_TABLE_FORM } as AddTableForm,
            errors: addTableFormErrors,
            submit: async (form) => {
                const { start_syncing, ...body } = form
                const payload: AddTableRequestApi = { ...body, name: body.name.trim(), path: body.path.trim() }
                let schema: ExternalDataSourceSchema
                try {
                    schema = await addTableToSource(props.sourceId, payload)
                } catch (e: any) {
                    const attr = e instanceof ApiError ? e.attr : e?.attr
                    const message = readableErrorMessage(e)
                    if ((attr === 'name' || attr === 'path') && message) {
                        actions.setAddTableManualErrors({ [attr]: message })
                    } else {
                        lemonToast.error(message ?? 'Could not add the table.')
                    }
                    return
                }

                // Awaited here and not queued on the source page, so the sync still starts when the page closes.
                let syncError: string | null = null
                if (start_syncing) {
                    try {
                        await startSyncing(props.sourceId, schema.id)
                    } catch (e: any) {
                        syncError = readableErrorMessage(e) ?? 'Unknown error'
                    }
                }

                const sourceSettings = sourceSettingsLogic.findMounted({ id: props.sourceId })
                // pinned: analytics event names, renaming breaks dashboards
                posthog.capture('warehouse table added', {
                    source_type: sourceSettings?.values.source?.source_type,
                    file_format: payload.file_format,
                    start_syncing,
                })
                if (syncError) {
                    lemonToast.error(`The table was added, but its sync didn't start: ${syncError}`)
                } else {
                    lemonToast.success('Table added')
                }
                actions.closeAddTable()
                actions.resetAddTable()
                sourceSettings?.actions.loadSource()
            },
        },
    })),
    listeners(({ actions, values }) => ({
        openAddTable: () => {
            actions.resetAddTable()
        },
        editName: ({ name }) => {
            actions.setAddTableValue('name', name)
        },
        setAddTableValue: ({ name, value }) => {
            const field = Array.isArray(name) ? name[0] : name
            if (field === 'path' && !values.nameEdited) {
                actions.setAddTableValue('name', tableNameFromPath(String(value ?? '')))
            }
        },
    })),
])
