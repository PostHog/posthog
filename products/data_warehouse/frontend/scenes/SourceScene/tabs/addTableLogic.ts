export const ADD_TABLE_NAME_REGEX = /^[a-zA-Z_][a-zA-Z0-9_]*$/

const GLOB_CHARS = /[*?{[]/
const COMPRESSION_SUFFIX = /\.(gz|gzip|bz2|zst|zip|lz4|xz|snappy|br)$/i

export async function addTableToSource(sourceId: string, body: AddTableRequestApi): Promise<ExternalDataSourceSchema> {
    const schema = await externalDataSourcesAddTableCreate(String(ApiConfig.getCurrentProjectId()), sourceId, body)
    // The endpoint returns the same serializer as the entries of `source.schemas`.
    return schema as unknown as ExternalDataSourceSchema
}

export async function startSyncing(sourceId: string, schemaId: string): Promise<void> {
    await externalDataSourcesBulkUpdateSchemasPartialUpdate(String(ApiConfig.getCurrentProjectId()), sourceId, {
        schemas: [{ id: schemaId, should_sync: true }],
    })
}

/** A table name from the last part of a path that has no wildcard: the folder name, or the file name without extensions. */
export function tableNameFromPath(path: string): string {
    const segments = path.split('/').filter(Boolean)
    let index = segments.length - 1
    while (index >= 0 && GLOB_CHARS.test(segments[index])) {
        index--
    }
    if (index < 0) {
        return ''
    }
    let segment = segments[index]
    if (index === segments.length - 1) {
        segment = segment.replace(COMPRESSION_SUFFIX, '').replace(/\.[a-zA-Z0-9]{1,8}$/, '')
    }
    const name = segment
        .toLowerCase()
        .replace(/[^a-z0-9_]/g, '_')
        .replace(/_+/g, '_')
        .replace(/^_+|_+$/g, '')
    return /^[0-9]/.test(name) ? `_${name}` : name
}

export function addTableFormErrors({ name, path }: Partial<AddTableForm>): Record<string, string | undefined> {
    return {
        name: !name
            ? 'Please enter a name.'
            : !ADD_TABLE_NAME_REGEX.test(name)
              ? 'Invalid table name. Table names must start with a letter or underscore and contain only alphanumeric characters or underscores.'
              : undefined,
        path: !path?.trim() ? 'Please enter a path.' : undefined,
    }
}

