export const REPLACE_FILE_SUCCESS_MESSAGE = 'Replacing the file. The table updates when the import finishes.'

/** Which of the two requests a replacement is on. */
export type ReplaceFileStage = 'upload' | 'replace'

export interface ReplaceFileTarget {
    /** Null when the schema has no live table to replace the file of. */
    tableId: string | null
    tableName: string
    /** The schema the file belongs to, so the schema page can reload after a replacement. */
    schemaId: string
}

export interface ReplaceFileLogicProps {
    sourceId: string
}

export function replaceFileTarget(
    schema: Pick<ExternalDataSourceSchema, 'id' | 'name' | 'table' | 'table_id'>
): ReplaceFileTarget {
    return {
        tableId: schema.table_id ?? schema.table?.id ?? null,
        tableName: schema.table?.name ?? schema.name,
        schemaId: schema.id,
    }
}

export function replaceFileDisabledReason(
    schema: Pick<ExternalDataSourceSchema, 'status'> | undefined
): string | undefined {
    if (!schema) {
        return 'This source has no table'
    }
    return schema.status === ExternalDataSchemaStatus.Running
        ? 'An import is running. Replace the file once it finishes.'
        : undefined
}

/** The one supported format the file's extension names, or null when the extension names none or several. */
export function detectFileFormat(filename: string): FileUploadFormat | null {
    const matches = FILE_UPLOAD_FORMATS.map(({ format }) => format).filter(
        (format) => !fileFormatMismatchError(filename, format)
    )
    return matches.length === 1 ? matches[0] : null
}

export function replaceFileError(file: File | null, fileFormat: FileUploadFormat): string | null {
    if (!file) {
        return null
    }
    if (file.size > MAX_FILE_UPLOAD_SIZE_BYTES) {
        return 'This file is larger than the 50MB upload limit.'
    }
    return fileFormatMismatchError(file.name, fileFormat) ?? null
}

function apiErrorMessage(error: any, fallback: string): string {
    return error?.data?.message ?? error?.detail ?? error?.message ?? fallback
}

