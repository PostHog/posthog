export const replaceFileLogic = kea<replaceFileLogicType>([
    props({} as ReplaceFileLogicProps),
    key(({ sourceId }) => sourceId),
    path((key) => ['products', 'dataWarehouse', 'replaceFileLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        openReplaceFile: (target: ReplaceFileTarget) => ({ target }),
        closeReplaceFile: true,
        selectFile: (file: File | null) => ({ file }),
        setFileFormat: (fileFormat: FileUploadFormat) => ({ fileFormat }),
        submitReplaceFile: true,
        setReplaceStage: (stage: ReplaceFileStage) => ({ stage }),
        setUploadedBytes: (uploadedBytes: number) => ({ uploadedBytes }),
        replaceFileSuccess: (table: TableApi) => ({ table }),
        replaceFileFailure: (error: string) => ({ error }),
    }),
    reducers({
        target: [
            null as ReplaceFileTarget | null,
            {
                openReplaceFile: (_, { target }) => target,
                closeReplaceFile: () => null,
            },
        ],
        file: [
            null as File | null,
            {
                selectFile: (_, { file }) => file,
                openReplaceFile: () => null,
            },
        ],
        fileFormat: [
            'csv' as FileUploadFormat,
            {
                setFileFormat: (_, { fileFormat }) => fileFormat,
            },
        ],
        replaceStage: [
            null as ReplaceFileStage | null,
            {
                setReplaceStage: (_, { stage }) => stage,
                replaceFileSuccess: () => null,
                replaceFileFailure: () => null,
            },
        ],
        uploadedBytes: [
            0,
            {
                setUploadedBytes: (_, { uploadedBytes }) => uploadedBytes,
                openReplaceFile: () => 0,
                selectFile: () => 0,
            },
        ],
        replaceError: [
            null as string | null,
            {
                replaceFileFailure: (_, { error }) => error,
                openReplaceFile: () => null,
                selectFile: () => null,
                setFileFormat: () => null,
                setReplaceStage: () => null,
            },
        ],
    }),
    selectors({
        isReplaceFileModalOpen: [(s) => [s.target], (target: ReplaceFileTarget | null): boolean => target !== null],
        isReplacing: [
            (s) => [s.replaceStage],
            (replaceStage: ReplaceFileStage | null): boolean => replaceStage !== null,
        ],
        fileError: [
            (s) => [s.file, s.fileFormat],
            (file: File | null, fileFormat: FileUploadFormat): string | null => replaceFileError(file, fileFormat),
        ],
        uploadPercent: [
            (s) => [s.uploadedBytes, s.file],
            (uploadedBytes: number, file: File | null): number => {
                if (!file?.size) {
                    return 0
                }
                // Multipart framing makes the sent byte count overshoot the file size at the end.
                return Math.min(100, Math.round((uploadedBytes / file.size) * 100))
            },
        ],
    }),
    listeners(({ actions, values, props }) => ({
        selectFile: ({ file }) => {
            const detected = file ? detectFileFormat(file.name) : null
            if (detected) {
                actions.setFileFormat(detected)
            }
        },
        submitReplaceFile: async () => {
            // The stage is set before the first await, so a second submit while one is in flight stops here.
            if (values.replaceStage !== null) {
                return
            }
            const { file, fileFormat, target, fileError, currentTeamId } = values
            if (!file || !target || fileError || !currentTeamId) {
                return
            }
            const projectId = String(currentTeamId)
            if (!target.tableId) {
                actions.replaceFileFailure(
                    `Could not find the table ${target.tableName}. Refresh the page and try again.`
                )
                return
            }
            const { tableId } = target
            actions.setReplaceStage('upload')

            const formData = new FormData()
            formData.append('file', file)
            formData.append('file_format', fileFormat)

            let upload
            try {
                // The generated client sends uploads with fetch, which cannot report upload progress.
                // nosemgrep: prefer-codegen-api-namespaced-data_warehouse
                upload = await api.dataWarehouseTables.uploadFile(formData, {
                    onUploadProgress: ({ loaded }) => actions.setUploadedBytes(loaded),
                })
            } catch (e: any) {
                posthog.capture('warehouse file replace failed', { stage: 'upload', file_format: fileFormat })
                actions.replaceFileFailure(apiErrorMessage(e, 'Could not upload the file.'))
                return
            }

            actions.setReplaceStage('replace')
            try {
                const table = await warehouseTablesReplaceFileCreate(projectId, tableId, {
                    upload_id: upload.upload_id,
                    filename: upload.filename,
                    file_format: fileFormat,
                })
                // pinned: analytics event names, renaming breaks dashboards
                posthog.capture('warehouse file replaced', { file_format: fileFormat })
                actions.replaceFileSuccess(table)
            } catch (e: any) {
                posthog.capture('warehouse file replace failed', { stage: 'replace', file_format: fileFormat })
                actions.replaceFileFailure(apiErrorMessage(e, 'Could not replace the file.'))
            }
        },
        replaceFileSuccess: () => {
            lemonToast.success(REPLACE_FILE_SUCCESS_MESSAGE)
            const schemaId = values.target?.schemaId
            actions.closeReplaceFile()
            sourceSettingsLogic.findMounted({ id: props.sourceId })?.actions.loadSource()
            if (schemaId) {
                schemaSceneLogic.findMounted({ sourceId: props.sourceId, schemaId })?.actions.loadSchema()
            }
        },
    })),
])
