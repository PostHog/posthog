import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
} from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import {
    warehouseTablesConfigureWarehouseSyncCreate,
    warehouseTablesWarehouseSyncRetrieve,
} from 'products/data_warehouse/frontend/generated/api'
import type { ExternalTableSyncSettingsApi } from 'products/data_warehouse/frontend/generated/api.schemas'

export interface ExternalTableSyncLogicProps {
    tableId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface externalTableSyncLogicValues {
    currentTeamId: number | null // teamLogic
    enabled: boolean
    intervalMinutes: number
    loadError: boolean
    settings: ExternalTableSyncSettingsApi | null
    settingsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface externalTableSyncLogicActions {
    loadExternalTableSync: () => any
    loadExternalTableSyncFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadExternalTableSyncSuccess: (
        settings: ExternalTableSyncSettingsApi,
        payload?: any
    ) => {
        settings: ExternalTableSyncSettingsApi
        payload?: any
    }
    saveExternalTableSync: () => any
    saveExternalTableSyncFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    saveExternalTableSyncSuccess: (
        settings: ExternalTableSyncSettingsApi,
        payload?: any
    ) => {
        settings: ExternalTableSyncSettingsApi
        payload?: any
    }
    saveSettings: () => {
        value: true
    }
    setEnabled: (enabled: boolean) => {
        enabled: boolean
    }
    setIntervalMinutes: (intervalMinutes: number) => {
        intervalMinutes: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface externalTableSyncLogicMeta {
    key: string
}

export type externalTableSyncLogicType = MakeLogicType<
    externalTableSyncLogicValues,
    externalTableSyncLogicActions,
    ExternalTableSyncLogicProps,
    externalTableSyncLogicMeta
>

export const externalTableSyncLogic: LogicWrapper<externalTableSyncLogicType> = kea<externalTableSyncLogicType>([
    props({} as ExternalTableSyncLogicProps),
    key((props) => props.tableId),
    path((key) => ['products', 'data_warehouse', 'externalTableSyncLogic', key]),
    connect({ values: [teamLogic, ['currentTeamId']] }),
    actions({
        setEnabled: (enabled: boolean) => ({ enabled }),
        setIntervalMinutes: (intervalMinutes: number) => ({ intervalMinutes }),
        saveSettings: true,
    }),
    loaders(({ values, props }) => ({
        settings: [
            null as ExternalTableSyncSettingsApi | null,
            {
                loadExternalTableSync: async (): Promise<ExternalTableSyncSettingsApi> => {
                    if (!values.currentTeamId) {
                        throw new Error('Select a project to load sync settings.')
                    }
                    return await warehouseTablesWarehouseSyncRetrieve(String(values.currentTeamId), props.tableId)
                },
                saveExternalTableSync: async (): Promise<ExternalTableSyncSettingsApi> => {
                    if (!values.currentTeamId) {
                        throw new Error('Select a project to save sync settings.')
                    }
                    return await warehouseTablesConfigureWarehouseSyncCreate(
                        String(values.currentTeamId),
                        props.tableId,
                        {
                            enabled: values.enabled,
                            interval_minutes: values.intervalMinutes,
                        }
                    )
                },
            },
        ],
    })),
    reducers({
        enabled: [
            false,
            {
                setEnabled: (_, { enabled }) => enabled,
                loadExternalTableSyncSuccess: (_, { settings }) => settings.enabled,
                saveExternalTableSyncSuccess: (_, { settings }) => settings.enabled,
            },
        ],
        intervalMinutes: [
            60,
            {
                setIntervalMinutes: (_, { intervalMinutes }) => intervalMinutes,
                loadExternalTableSyncSuccess: (_, { settings }) => settings.interval_minutes,
                saveExternalTableSyncSuccess: (_, { settings }) => settings.interval_minutes,
            },
        ],
        loadError: [
            false,
            {
                loadExternalTableSync: () => false,
                loadExternalTableSyncFailure: () => true,
                loadExternalTableSyncSuccess: () => false,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        saveSettings: () => {
            if (!values.settingsLoading) {
                actions.saveExternalTableSync()
            }
        },
    })),
    afterMount(({ actions }) => actions.loadExternalTableSync()),
])
