export const warehouseLoginsLogic = kea<warehouseLoginsLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'scenes', 'WarehouseAccessScene', 'warehouseLoginsLogic']),
    connect(() => ({
        values: [
            organizationLogic,
            ['currentOrganization'],
            teamLogic,
            ['currentTeamId'],
            warehouseConsoleLogic,
            ['initialPassword', 'trinoConnection'],
        ],
        actions: [warehouseConsoleLogic, ['clearInitialPassword']],
    })),
    actions({
        openNewLogin: true,
        closeNewLogin: true,
        setNewLoginTeamId: (teamId: number) => ({ teamId }),
        setNewLoginMode: (mode: LoginModeEnumApi) => ({ mode }),
        createLogin: true,
        createLoginDone: true,
        rotateLogin: (username: string) => ({ username }),
        setLoginDisabled: (username: string, disabled: boolean) => ({ username, disabled }),
        requestDeleteLogin: (username: string | null) => ({ username }),
        deleteLogin: (username: string) => ({ username }),
        loginActionDone: true,
        revealPassword: (reveal: RevealedLoginPassword) => ({ reveal }),
        closeReveal: true,
    }),
    loaders({
        logins: [
            null as WarehouseLoginApi[] | null,
            {
                loadLogins: async () => (await managedWarehouseConsoleLoginsRetrieve(currentProjectId())).logins,
            },
        ],
    }),
    reducers({
        loginsFailed: [
            false,
            {
                loadLogins: () => false,
                loadLoginsSuccess: () => false,
                loadLoginsFailure: () => true,
            },
        ],
        busyUsername: [
            null as string | null,
            {
                rotateLogin: (_, { username }) => username,
                setLoginDisabled: (_, { username }) => username,
                deleteLogin: (_, { username }) => username,
                loginActionDone: () => null,
            },
        ],
        isCreating: [
            false,
            {
                createLogin: () => true,
                createLoginDone: () => false,
            },
        ],
        newLoginOpen: [
            false,
            {
                openNewLogin: () => true,
                closeNewLogin: () => false,
            },
        ],
        newLoginTeamId: [null as number | null, { setNewLoginTeamId: (_, { teamId }) => teamId }],
        newLoginMode: ['reader' as LoginModeEnumApi, { setNewLoginMode: (_, { mode }) => mode }],
        pendingDeleteUsername: [
            null as string | null,
            {
                requestDeleteLogin: (_, { username }) => username,
                deleteLogin: () => null,
            },
        ],
        // The password reaches the page once. Closing the reveal drops it.
        revealedPassword: [
            null as RevealedLoginPassword | null,
            {
                revealPassword: (_, { reveal }) => reveal,
                closeReveal: () => null,
            },
        ],
    }),
    selectors({
        projects: [
            (s) => [s.currentOrganization],
            (organization: OrganizationType | null): WarehouseLoginProject[] =>
                (organization?.teams ?? []).map((team: { id: number; name: string }) => ({
                    id: team.id,
                    name: team.name,
                })),
        ],
        // Creating a login for a project and access that already has one gives that login a new password.
        existingLogin: [
            (s) => [s.logins, s.effectiveNewLoginTeamId, s.newLoginMode],
            (
                logins: WarehouseLoginApi[] | null,
                teamId: number | null,
                mode: LoginModeEnumApi
            ): WarehouseLoginApi | null =>
                logins?.find(
                    (login) =>
                        login.team_id === teamId &&
                        login.kind === (mode === 'reader' ? 'project_reader' : 'project_user')
                ) ?? null,
        ],
        // The one-time password on screen: a project login's, or the root login's after a reset.
        activeReveal: [
            (s) => [s.revealedPassword, s.initialPassword, s.trinoConnection],
            (
                revealed: RevealedLoginPassword | null,
                initialPassword: string | null,
                connection: { username: string } | null
            ): RevealedLoginPassword | null =>
                revealed ??
                (initialPassword
                    ? { username: connection?.username ?? 'root', password: initialPassword, reason: 'reset' }
                    : null),
        ],
        effectiveNewLoginTeamId: [
            (s) => [s.newLoginTeamId, s.projects, s.currentTeamId],
            (selected: number | null, projects: WarehouseLoginProject[], currentTeamId: number | null): number | null =>
                selected ?? (projects.some((p) => p.id === currentTeamId) ? currentTeamId : (projects[0]?.id ?? null)),
        ],
    }),
    listeners(({ actions, values }) => ({
        closeReveal: () => actions.clearInitialPassword(),
        createLogin: async () => {
            const teamId = values.effectiveNewLoginTeamId
            if (teamId === null) {
                actions.createLoginDone()
                return
            }
            try {
                const result = await managedWarehouseConsoleLoginsCreate(currentProjectId(), {
                    team_id: teamId,
                    mode: values.newLoginMode,
                })
                posthog.capture('warehouse access login created', { mode: values.newLoginMode })
                actions.closeNewLogin()
                actions.revealPassword({
                    username: result.login.username,
                    password: result.password,
                    reason: 'created',
                })
                actions.loadLogins()
            } catch (e) {
                lemonToast.error(consoleErrorMessage(e, "Couldn't create the login. Try again."))
            }
            actions.createLoginDone()
        },
        rotateLogin: async ({ username }) => {
            try {
                const result = await managedWarehouseConsoleLoginsRotateCreate(currentProjectId(), username)
                posthog.capture('warehouse access login rotated')
                actions.revealPassword({ username, password: result.password, reason: 'rotated' })
                actions.loadLogins()
            } catch (e) {
                lemonToast.error(consoleErrorMessage(e, "Couldn't rotate the password. Try again."))
            }
            actions.loginActionDone()
        },
        setLoginDisabled: async ({ username, disabled }) => {
            try {
                await managedWarehouseConsoleLoginsPartialUpdate(currentProjectId(), username, { disabled })
                posthog.capture('warehouse access login toggled', { disabled })
                actions.loadLogins()
            } catch (e) {
                lemonToast.error(
                    consoleErrorMessage(e, `Couldn't ${disabled ? 'disable' : 'enable'} the login. Try again.`)
                )
            }
            actions.loginActionDone()
        },
        deleteLogin: async ({ username }) => {
            try {
                await managedWarehouseConsoleLoginsDestroy(currentProjectId(), username)
                posthog.capture('warehouse access login deleted')
                actions.loadLogins()
            } catch (e) {
                lemonToast.error(consoleErrorMessage(e, "Couldn't delete the login. Try again."))
            }
            actions.loginActionDone()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadLogins()
    }),
])
