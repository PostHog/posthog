export const warehouseHomeLogic = kea<warehouseHomeLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'scenes', 'WarehouseHomeScene', 'warehouseHomeLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], dataWarehouseSetupLogic, ['setupStatus']],
    })),
    loaders(({ values }) => ({
        savedQueryCount: [
            null as number | null,
            {
                // Only the total is needed, so skip the column definitions, which cost the most to serialize.
                loadSavedQueryCount: async () =>
                    (await warehouseSavedQueriesList(String(values.currentTeamId), { include_columns: false })).count,
            },
        ],
        healthIssues: [
            null as DataHealthIssueApi[] | null,
            {
                loadWarehouseHomeHealthIssues: async () =>
                    (await dataWarehouseDataHealthIssuesRetrieve(String(values.currentTeamId))).results,
            },
        ],
        jobStats: [
            null as PipelineJobStatsResponseApi | null,
            {
                loadWarehouseHomeJobStats: async (_: void, breakpoint) => {
                    const response = await dataWarehouseJobStatsRetrieve(String(values.currentTeamId), {
                        days: values.jobStatsDays,
                    })
                    // A newer window was picked while this one loaded.
                    breakpoint()
                    return response
                },
            },
        ],
        recentRuns: [
            null as PipelineActivityRowApi[] | null,
            {
                loadWarehouseHomeRecentRuns: async () => {
                    const [finished, running] = await Promise.all([
                        dataWarehouseCompletedActivityRetrieve(String(values.currentTeamId), {
                            outcome: 'all',
                            limit: RECENT_RUNS_LIMIT,
                        }),
                        dataWarehouseRunningActivityRetrieve(String(values.currentTeamId), {
                            limit: RECENT_RUNS_LIMIT,
                        }),
                    ])
                    // In-flight runs come first, so a sync that just started is at the top.
                    const runningRuns = running.results ?? []
                    const runningIds = new Set(runningRuns.map((run) => run.id))
                    // A run can show in both lists while it finishes, so keep only the running copy.
                    const finishedRuns = (finished.results ?? []).filter((run) => !runningIds.has(run.id))
                    return [...runningRuns, ...finishedRuns].slice(0, RECENT_RUNS_LIMIT)
                },
            },
        ],
    })),
    actions({
        setJobStatsDays: (days: JobStatsDays) => ({ days }),
        retryJobStats: true,
    }),
    reducers({
        jobStatsDays: [
            DEFAULT_JOB_STATS_DAYS as JobStatsDays,
            {
                setJobStatsDays: (_, { days }) => days,
            },
        ],
        jobStatsFailed: [
            false,
            { loadWarehouseHomeJobStats: () => false, loadWarehouseHomeJobStatsFailure: () => true },
        ],
        savedQueryCountFailed: [false, { loadSavedQueryCount: () => false, loadSavedQueryCountFailure: () => true }],
        healthIssuesFailed: [
            false,
            { loadWarehouseHomeHealthIssues: () => false, loadWarehouseHomeHealthIssuesFailure: () => true },
        ],
        recentRunsFailed: [
            false,
            { loadWarehouseHomeRecentRuns: () => false, loadWarehouseHomeRecentRunsFailure: () => true },
        ],
    }),
    selectors({
        sourceStep: [
            (s) => [s.setupStatus],
            (setupStatus: ProductSetupStatus): WarehouseStepState =>
                setupStatus === 'has-data' || setupStatus === 'waiting-for-data'
                    ? 'done'
                    : // 'unknown' means detection failed or access was denied, so show the step as not done instead of spinning.
                      setupStatus === 'loading'
                      ? 'loading'
                      : 'todo',
        ],
        viewStep: [
            (s) => [s.savedQueryCount, s.savedQueryCountFailed],
            // A failed count shows the step as not done rather than spinning forever.
            (count: number | null, failed: boolean): WarehouseStepState =>
                count === null ? (failed ? 'todo' : 'loading') : count > 0 ? 'done' : 'todo',
        ],
        warehouseIssues: [
            (s) => [s.healthIssues],
            (issues: DataHealthIssueApi[] | null): DataHealthIssueApi[] | null =>
                issues === null
                    ? null
                    : issues
                          .filter((issue) => WAREHOUSE_ISSUE_TYPES.includes(issue.type))
                          // A webhook table is pushed to on the vendor's schedule, so it cannot have stopped syncing.
                          .filter((issue) => issue.sync_type !== 'webhook')
                          .sort((a, b) => severity(a.status) - severity(b.status)),
        ],
        runBuckets: [
            (s) => [s.jobStats],
            (stats: PipelineJobStatsResponseApi | null): RunBucket[] => (stats ? fillRunBuckets(stats) : []),
        ],
        runSuccess: [
            (s) => [s.jobStats],
            (stats: PipelineJobStatsResponseApi | null): PipelineTile | null => (stats ? runSuccessTile(stats) : null),
        ],
        syncTile: [
            (s) => [s.jobStats],
            (stats: PipelineJobStatsResponseApi | null): PipelineTile | null =>
                stats ? jobCountsTile(stats.external_data_jobs) : null,
        ],
        viewTile: [
            (s) => [s.jobStats],
            (stats: PipelineJobStatsResponseApi | null): PipelineTile | null =>
                stats ? jobCountsTile(stats.modeling_jobs) : null,
        ],
        attentionTile: [
            (s) => [s.warehouseIssues, s.issueCountsByStatus],
            (
                issues: DataHealthIssueApi[] | null,
                countsByStatus: [string, number][]
            ): (PipelineTile & { danger: boolean }) | null =>
                issues === null ? null : needsAttentionTile(issues, countsByStatus),
        ],
        issueCountsByStatus: [
            (s) => [s.warehouseIssues],
            (issues: DataHealthIssueApi[] | null): [string, number][] => {
                const counts = new Map<string, number>()
                for (const issue of issues ?? []) {
                    counts.set(issue.status, (counts.get(issue.status) ?? 0) + 1)
                }
                return [...counts.entries()].sort(([a], [b]) => severity(a) - severity(b))
            },
        ],
    }),
    listeners(({ actions }) => ({
        setJobStatsDays: ({ days }) => {
            posthog.capture('warehouse overview window changed', { days })
            actions.loadWarehouseHomeJobStats()
        },
        retryJobStats: () => {
            posthog.capture('warehouse overview stats retry clicked')
            actions.loadWarehouseHomeJobStats()
        },
    })),
    afterMount(({ actions, cache }) => {
        actions.loadWarehouseHomeJobStats()
        actions.loadSavedQueryCount()
        actions.loadWarehouseHomeHealthIssues()
        actions.loadWarehouseHomeRecentRuns()
        // Syncs finish while the user is in another tab, so health and runs reload on return instead of on a timer.
        cache.disposables.add(
            () => {
                const onVisibilityChange = (): void => {
                    if (document.visibilityState === 'visible') {
                        actions.loadWarehouseHomeJobStats()
                        actions.loadWarehouseHomeHealthIssues()
                        actions.loadWarehouseHomeRecentRuns()
                    }
                }
                document.addEventListener('visibilitychange', onVisibilityChange)
                return () => document.removeEventListener('visibilitychange', onVisibilityChange)
            },
            'reloadOnVisible',
            { pauseOnPageHidden: false }
        )
    }),
])
