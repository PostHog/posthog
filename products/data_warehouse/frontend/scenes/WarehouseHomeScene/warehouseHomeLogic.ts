import { MakeLogicType, afterMount, connect, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import type { ProductSetupStatus } from 'lib/components/ProductEmptyState/types'
import { teamLogic } from 'scenes/teamLogic'

import { dataWarehouseSetupLogic } from '../../emptyState/dataWarehouseSetupLogic'
import {
    dataWarehouseCompletedActivityRetrieve,
    dataWarehouseDataHealthIssuesRetrieve,
    dataWarehouseRunningActivityRetrieve,
    warehouseSavedQueriesList,
} from '../../generated/api'
import type { DataHealthIssueApi, PipelineActivityRowApi } from '../../generated/api.schemas'

export type WarehouseStepState = 'loading' | 'todo' | 'done'

export const RECENT_RUNS_LIMIT = 5
export const HEALTH_ISSUES_LIMIT = 5

// The endpoint answers for every pipeline. Destinations and transformations here are batch exports and CDP, not the warehouse.
const WAREHOUSE_ISSUE_TYPES = ['external_data_sync', 'source', 'materialized_view']

// Most severe first, so the worst problem is the one a reader sees.
const ISSUE_SEVERITY: Record<string, number> = { failed: 0, billing_limit: 1, degraded: 2, disabled: 3 }

function severity(status: string): number {
    return ISSUE_SEVERITY[status] ?? 99
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseHomeLogicValues {
    setupStatus: ProductSetupStatus // dataWarehouseSetupLogic
    currentTeamId: number | null // teamLogic
    healthIssues: DataHealthIssueApi[] | null
    healthIssuesFailed: boolean
    healthIssuesLoading: boolean
    issueCountsByStatus: [string, number][]
    recentRuns: PipelineActivityRowApi[] | null
    recentRunsFailed: boolean
    recentRunsLoading: boolean
    savedQueryCount: number | null
    savedQueryCountFailed: boolean
    savedQueryCountLoading: boolean
    sourceStep: WarehouseStepState
    viewStep: WarehouseStepState
    warehouseIssues: DataHealthIssueApi[] | null
}

