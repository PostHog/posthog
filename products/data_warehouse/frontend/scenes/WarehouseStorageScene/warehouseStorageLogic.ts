export type warehouseStorageLogicType = MakeLogicType<
    warehouseStorageLogicValues,
    warehouseStorageLogicActions,
    Record<string, any>,
    warehouseStorageLogicMeta
>

export const warehouseStorageLogic = kea<warehouseStorageLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'scenes', 'WarehouseStorageScene', 'warehouseStorageLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], warehouseConsoleLogic, ['consoleState']],
        actions: [warehouseConsoleLogic, ['loadWarehouseStatusSuccess']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        retryStorage: true,
        ensureLoaded: true,
    }),
    reducers({
        search: [
            '',
            {
                setSearch: (_, { search }) => search,
            },
        ],
        storageFailed: [
            false,
            {
                loadStorage: () => false,
                loadStorageSuccess: () => false,
                loadStorageFailure: () => true,
            },
        ],
    }),
    loaders(({ values }) => ({
        storage: [
            null as StorageResponseApi | null,
            {
                loadStorage: async () => await managedWarehouseConsoleStorageRetrieve(String(values.currentTeamId)),
            },
        ],
    })),
    selectors({
        tableRows: [
            (s) => [s.storage],
            (storage: StorageResponseApi | null): StorageTableRow[] =>
                (storage?.tables ?? [])
                    .map((table) => ({
                        ...table,
                        size_bytes: table.data_bytes + table.delete_bytes,
                        qualified_name: `${table.schema}.${table.table}`,
                    }))
                    .sort((a, b) => b.size_bytes - a.size_bytes || a.qualified_name.localeCompare(b.qualified_name)),
        ],
        filteredTableRows: [
            (s) => [s.tableRows, s.search],
            (rows: StorageTableRow[], search: string): StorageTableRow[] => {
                const needle = search.trim().toLowerCase()
                return needle ? rows.filter((row) => row.qualified_name.toLowerCase().includes(needle)) : rows
            },
        ],
        maintenanceFields: [
            (s) => [s.storage],
            (storage: StorageResponseApi | null): MaintenanceField[] => describeMaintenance(storage?.maintenance),
        ],
    }),
    listeners(({ actions, values }) => ({
        retryStorage: () => {
            posthog.capture('warehouse storage retry clicked')
            actions.loadStorage()
        },
        // One event per pause in typing, not one per key.
        setSearch: async ({ search }, breakpoint) => {
            await breakpoint(800)
            if (search.trim()) {
                posthog.capture('warehouse storage search used', { result_count: values.filteredTableRows.length })
            }
        },
        loadWarehouseStatusSuccess: () => actions.ensureLoaded(),
        ensureLoaded: () => {
            if (values.consoleState === 'ready' && !values.storage && !values.storageLoading) {
                actions.loadStorage()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.ensureLoaded()
    }),
])
