export interface StorageTableRow extends StorageTableApi {
    /** Live data plus delete files, the bytes the table occupies. */
    size_bytes: number
    qualified_name: string
}

export interface MaintenanceField {
    label: string
    value: string
}

const MAX_MAINTENANCE_DEPTH = 2

function humanizeKey(key: string): string {
    const text = key.replaceAll('_', ' ').trim()
    return text.charAt(0).toUpperCase() + text.slice(1)
}

function describeValue(value: unknown): string | null {
    if (value === null || value === undefined) {
        return null
    }
    if (typeof value === 'boolean') {
        return value ? 'Yes' : 'No'
    }
    if (typeof value === 'number' || typeof value === 'string') {
        return String(value)
    }
    return null
}

/** The maintenance status is opaque JSON from the control plane, so this lists only the scalar values it finds. */
export function describeMaintenance(maintenance: Record<string, unknown> | null | undefined): MaintenanceField[] {
    if (!maintenance) {
        return []
    }
    const fields: MaintenanceField[] = []
    const walk = (node: Record<string, unknown>, prefix: string, depth: number): void => {
        for (const [key, value] of Object.entries(node)) {
            const label = prefix ? `${prefix} ${key.replaceAll('_', ' ')}` : humanizeKey(key)
            const text = describeValue(value)
            if (text !== null) {
                fields.push({ label, value: text })
            } else if (value && typeof value === 'object' && !Array.isArray(value) && depth < MAX_MAINTENANCE_DEPTH) {
                walk(value as Record<string, unknown>, label, depth + 1)
            }
        }
    }
    walk(maintenance, '', 1)
    return fields
}

function quoteIdentifier(name: string): string {
    return `"${name.replaceAll('"', '""')}"`
}

/** The SQL editor link that previews the first rows of a table, on the managed warehouse's Trino engine. */
export function tablePreviewUrl(schema: string, table: string): string {
    return urls.sqlEditor({
        query: `SELECT * FROM ${quoteIdentifier(schema)}.${quoteIdentifier(table)} LIMIT 100`,
        executionTarget: 'managed_trino',
    })
}

