function keyErrorMessage(e: any): string {
    // A 4xx carries the reason, for example that Fivetran rejected the key.
    if (e?.status >= 400 && e?.status < 500 && e?.detail) {
        return e.detail
    }
    if (!e?.status) {
        return "PostHog couldn't reach the server. An ad blocker or browser extension may be blocking the request. Pause it or switch networks, then try again."
    }
    return "PostHog couldn't save the key. Try again in a minute."
}

export const migrationConnectSceneLogic = kea<migrationConnectSceneLogicType>([
    path(['products', 'dataWarehouse', 'migrationConnectSceneLogic']),
    actions({
        setStartedMigration: (migration: WarehouseMigrationApi) => ({ migration }),
    }),
    reducers({
        startedMigration: [
            null as WarehouseMigrationApi | null,
            {
                setStartedMigration: (_, { migration }) => migration,
            },
        ],
    }),
    selectors({
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: Scene.Sources,
                    name: 'Sources',
                    path: urls.sources(),
                    iconType: 'data_pipeline',
                },
                {
                    key: Scene.DataWarehouseMigrationConnect,
                    name: 'Import from Fivetran',
                    iconType: 'data_pipeline',
                },
            ],
        ],
    }),
    forms(({ actions }) => ({
        keyForm: {
            defaults: { api_key: '', api_secret: '' } as MigrationKeyForm,
            errors: ({ api_key, api_secret }: MigrationKeyForm) => ({
                api_key: api_key.trim() ? undefined : 'Enter the API key',
                api_secret: api_secret.trim() ? undefined : 'Enter the API secret',
            }),
            submit: async ({ api_key, api_secret }: MigrationKeyForm) => {
                try {
                    const migration = await warehouseMigrationsCreate(String(ApiConfig.getCurrentTeamId()), {
                        provider: 'fivetran',
                        api_key: api_key.trim(),
                        api_secret: api_secret.trim(),
                    })
                    actions.setStartedMigration(migration)
                } catch (e: any) {
                    if (e?.status >= 500) {
                        posthog.captureException(e)
                    }
                    lemonToast.error(keyErrorMessage(e))
                }
            },
        },
    })),
])
