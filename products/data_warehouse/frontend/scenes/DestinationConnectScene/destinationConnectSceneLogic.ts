/** Whether the saved connection reached the agent that shared the link. Only links with a connect token try. */
export type HandBackStatus = 'sending' | 'sent' | 'failed'

export interface PrefilledField {
    label: string
    value: string
}

export const destinationConnectSceneLogic = kea<destinationConnectSceneLogicType>([
    path(['products', 'dataWarehouse', 'destinationConnectSceneLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        setKind: (kind: string | null) => ({ kind }),
        setConnectToken: (connectToken: string | null) => ({ connectToken }),
        setModalOpen: (open: boolean) => ({ open }),
        setIntegrationId: (integrationId: number) => ({ integrationId }),
        completeSetup: (integrationId: number, migrationItemId: string | null) => ({ integrationId, migrationItemId }),
        loadMigrationPrefill: (migrationId: string, itemId: string) => ({ migrationId, itemId }),
        migrationPrefillLoaded: (
            vendorConfig: Record<string, unknown> | null,
            creator: WarehouseMigrationCreatorApi | null
        ) => ({ vendorConfig, creator }),
        clearMigrationPrefill: true,
        setPrefillConfirmed: (confirmed: boolean) => ({ confirmed }),
        setHandBackStatus: (status: HandBackStatus) => ({ status }),
    }),
    reducers({
        connectToken: [
            null as string | null,
            {
                setConnectToken: (_, { connectToken }) => connectToken,
            },
        ],
        handBackStatus: [
            null as HandBackStatus | null,
            {
                setKind: () => null,
                loadMigrationPrefill: () => null,
                clearMigrationPrefill: () => null,
                setHandBackStatus: (_, { status }) => status,
            },
        ],
        kind: [
            null as string | null,
            {
                setKind: (_, { kind }) => kind,
            },
        ],
        isModalOpen: [
            true,
            {
                setKind: () => true,
                loadMigrationPrefill: () => true,
                clearMigrationPrefill: () => true,
                setModalOpen: (_, { open }) => open,
            },
        ],
        integrationId: [
            null as number | null,
            {
                setKind: () => null,
                // A connection saved for one migration item must not show as saved for the next one.
                loadMigrationPrefill: () => null,
                clearMigrationPrefill: () => null,
                setIntegrationId: (_, { integrationId }) => integrationId,
            },
        ],
        migrationPrefillLoading: [
            false,
            {
                loadMigrationPrefill: () => true,
                migrationPrefillLoaded: () => false,
                clearMigrationPrefill: () => false,
            },
        ],
        migrationItemId: [
            null as string | null,
            {
                loadMigrationPrefill: (_, { itemId }) => itemId,
                clearMigrationPrefill: () => null,
            },
        ],
        vendorConfig: [
            null as Record<string, unknown> | null,
            {
                loadMigrationPrefill: () => null,
                migrationPrefillLoaded: (_, { vendorConfig }) => vendorConfig,
                clearMigrationPrefill: () => null,
            },
        ],
        migrationCreator: [
            null as WarehouseMigrationCreatorApi | null,
            {
                loadMigrationPrefill: () => null,
                migrationPrefillLoaded: (_, { creator }) => creator,
                clearMigrationPrefill: () => null,
            },
        ],
        prefillConfirmed: [
            false,
            {
                setPrefillConfirmed: (_, { confirmed }) => confirmed,
                loadMigrationPrefill: () => false,
                clearMigrationPrefill: () => false,
            },
        ],
    }),
    selectors({
        destinationDefinition: [
            (s) => [s.kind],
            (kind: string | null): WarehouseDestinationDefinition | null =>
                kind
                    ? (Object.values(WAREHOUSE_DESTINATIONS).find((definition) =>
                          definition.integrationKinds.includes(kind as IntegrationKind)
                      ) ?? null)
                    : null,
        ],
        integrationSetup: [
            (s) => [s.kind],
            (kind: string | null): IntegrationSetupDefinition | null =>
                kind ? (getIntegrationSetup(kind) ?? null) : null,
        ],
        lockedSetupValues: [
            (s) => [s.integrationSetup, s.vendorConfig],
            (
                integrationSetup: IntegrationSetupDefinition | null,
                vendorConfig: Record<string, unknown> | null
            ): Record<string, any> | undefined => {
                const keys = integrationSetup?.vendorConfigKeys
                if (!keys || !vendorConfig) {
                    return undefined
                }
                return Object.fromEntries(
                    Object.entries(keys)
                        .filter(([, vendorKey]) => vendorConfig[vendorKey] != null && vendorConfig[vendorKey] !== '')
                        .map(([field, vendorKey]) => [field, vendorConfig[vendorKey]])
                )
            },
        ],
        prefilledFieldRows: [
            (s) => [s.lockedSetupValues],
            (lockedSetupValues: Record<string, any> | undefined): PrefilledField[] =>
                Object.entries(lockedSetupValues ?? {}).map(([key, value]) => ({
                    label: key.charAt(0).toUpperCase() + key.slice(1).replace(/_/g, ' '),
                    value: String(value),
                })),
        ],
        // The user confirms a prefilled server before the credentials form opens.
        setupModalOpen: [
            (s) => [s.isModalOpen, s.integrationId, s.lockedSetupValues, s.prefillConfirmed],
            (
                isModalOpen: boolean,
                integrationId: number | null,
                lockedSetupValues: Record<string, any> | undefined,
                prefillConfirmed: boolean
            ): boolean => isModalOpen && integrationId === null && (!lockedSetupValues || prefillConfirmed),
        ],
        setupLock: [
            (s) => [s.lockedSetupValues],
            (lockedSetupValues: Record<string, any> | undefined): LockedSetupValues | undefined =>
                lockedSetupValues && {
                    values: lockedSetupValues,
                    reason: 'Set by the migration. To change it, set up a new destination instead.',
                },
        ],
        showPrefillConfirm: [
            (s) => [s.lockedSetupValues, s.integrationId],
            (lockedSetupValues: Record<string, any> | undefined, integrationId: number | null): boolean =>
                !!lockedSetupValues && integrationId === null,
        ],
        openSetupDisabledReason: [
            (s) => [s.lockedSetupValues, s.prefillConfirmed],
            (lockedSetupValues: Record<string, any> | undefined, prefillConfirmed: boolean): string | undefined =>
                lockedSetupValues && !prefillConfirmed ? 'Confirm the server above first' : undefined,
        ],
        breadcrumbs: [
            (s) => [s.destinationDefinition],
            (destinationDefinition: WarehouseDestinationDefinition | null): Breadcrumb[] => [
                {
                    key: Scene.WarehouseDestinations,
                    name: 'Warehouse destinations',
                    path: urls.warehouseDestinations(),
                    iconType: 'warehouse_destination',
                },
                {
                    key: Scene.WarehouseDestinationConnect,
                    name: destinationDefinition
                        ? `Connect ${destinationTypeLabel(destinationDefinition.type)}`
                        : 'Connect destination',
                    iconType: 'warehouse_destination',
                },
            ],
        ],
    }),
    listeners(({ actions, values }) => ({
        setKind: () => {
            if (values.destinationDefinition) {
                posthog.capture('warehouse destination connect page viewed', {
                    integration_kind: values.kind,
                    destination_type: values.destinationDefinition.type,
                    from_migration: values.migrationItemId !== null,
                })
            }
        },
        setIntegrationId: async ({ integrationId }) => {
            posthog.capture('warehouse destination connection saved', {
                integration_kind: values.kind,
                destination_type: values.destinationDefinition?.type,
                from_migration: values.migrationItemId !== null,
                has_connect_token: values.connectToken !== null,
            })
            if (!values.connectToken || values.currentTeamId === null) {
                return
            }
            actions.setHandBackStatus('sending')
            try {
                await externalDataDestinationsConnectLinkCompleteCreate(String(values.currentTeamId), {
                    connect_token: values.connectToken,
                    integration_id: integrationId,
                })
                actions.setHandBackStatus('sent')
            } catch {
                actions.setHandBackStatus('failed')
            }
            posthog.capture('warehouse destination connection handed back', {
                integration_kind: values.kind,
                destination_type: values.destinationDefinition?.type,
                succeeded: values.handBackStatus === 'sent',
            })
        },
        completeSetup: ({ integrationId, migrationItemId }) => {
            // A save that finishes after the user moved to another item belongs to the item it started on.
            if (migrationItemId === values.migrationItemId) {
                actions.setIntegrationId(integrationId)
            }
        },
        loadMigrationPrefill: async ({ migrationId, itemId }, breakpoint) => {
            let vendorConfig: Record<string, unknown> | null = null
            let creator: WarehouseMigrationCreatorApi | null = null
            try {
                const item = await warehouseMigrationsItemsRetrieve(
                    String(ApiConfig.getCurrentTeamId()),
                    migrationId,
                    itemId
                )
                vendorConfig = item.proposal?.destination?.config ?? null
                creator = item.created_by ?? null
            } catch (e: any) {
                // The user can still fill the form by hand, so only a server error gets reported.
                if (e?.status >= 500) {
                    posthog.captureException(e)
                }
            }
            // Drops this response when the user opened another link meanwhile.
            breakpoint()
            if (values.migrationItemId !== itemId) {
                return
            }
            actions.migrationPrefillLoaded(vendorConfig, creator)
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.warehouseDestinationConnect()]: (_, searchParams) => {
            // Coming back to the same link must not overwrite what the user typed.
            const itemId = searchParams.migration_item_id ?? null
            if (searchParams.migration_id && itemId) {
                if (itemId !== values.migrationItemId) {
                    actions.loadMigrationPrefill(searchParams.migration_id, itemId)
                }
            } else if (values.migrationItemId !== null) {
                actions.clearMigrationPrefill()
            }
            // A hash change (the side panel opening) runs this again, and a reset would hide the saved id.
            const kind = searchParams.kind ?? null
            if (kind !== values.kind) {
                actions.setKind(kind)
            }
            const connectToken = typeof searchParams.token === 'string' ? searchParams.token : null
            if (connectToken !== values.connectToken) {
                actions.setConnectToken(connectToken)
            }
        },
    })),
])
