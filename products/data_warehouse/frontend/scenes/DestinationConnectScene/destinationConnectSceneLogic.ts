import { MakeLogicType, actions, kea, listeners, path, reducers, selectors } from 'kea'
import { urlToAction } from 'kea-router'
import posthog from 'posthog-js'

import 'lib/components/CyclotronJob/integrations/integrationSetups'
import {
    IntegrationSetupDefinition,
    getIntegrationSetup,
} from 'lib/components/CyclotronJob/integrations/integrationSetupRegistry'
import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { ApiConfig } from '~/lib/api'
import { Breadcrumb, IntegrationKind } from '~/types'

import { warehouseMigrationsItemsList } from 'products/warehouse_sources/frontend/generated/api'

import { destinationTypeLabel } from '../../shared/components/DestinationIcon'
import { WAREHOUSE_DESTINATIONS } from '../../shared/destinations/destinationDefinitions'
import type { WarehouseDestinationDefinition } from '../../shared/destinations/types'

