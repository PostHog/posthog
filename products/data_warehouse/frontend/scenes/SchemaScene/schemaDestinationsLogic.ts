export const schemaDestinationsLogic = kea<schemaDestinationsLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'scenes', 'SchemaScene', 'schemaDestinationsLogic']),
    props({} as SchemaDestinationsLogicProps),
    key((props: SchemaDestinationsLogicProps) => props.schemaId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        toggleDestination: (destinationId: string) => ({ destinationId }),
        setOverriding: (overriding: boolean) => ({ overriding }),
        save: true,
        clearOverride: true,
        resyncAfterAdding: true,
    }),
    loaders(({ values, props }: any) => ({
        destinations: [
            [] as ExternalDataDestinationApi[],
            {
                loadDestinations: async () => {
                    const response = await externalDataDestinationsList(String(values.currentTeamId))
                    return response.results ?? []
                },
            },
        ],
        override: [
            {
                destination_ids: null,
                inherits_from_source: true,
                effective_destination_ids: [],
            } as SchemaDestinationsResponse,
            {
                loadOverride: async () =>
                    (await externalDataSchemasDestinationsRetrieve(
                        String(values.currentTeamId),
                        props.schemaId
                    )) as SchemaDestinationsResponse,
                saveOverride: async (destinationIds: string[] | null) =>
                    (await externalDataSchemasDestinationsPartialUpdate(String(values.currentTeamId), props.schemaId, {
                        destination_ids: destinationIds,
                    })) as SchemaDestinationsResponse,
            },
        ],
    })),
    reducers({
        // Starts as whatever the table effectively syncs to, so switching from inheriting to
        // overriding does not silently change where data goes.
        draftDestinationIds: [
            [] as string[],
            {
                toggleDestination: (state: string[], { destinationId }: { destinationId: string }) =>
                    state.includes(destinationId)
                        ? state.filter((id) => id !== destinationId)
                        : [...state, destinationId],
                loadOverrideSuccess: (_: string[], { override }: { override: SchemaDestinationsResponse }) =>
                    override.effective_destination_ids ?? [],
                saveOverrideSuccess: (_: string[], { override }: { override: SchemaDestinationsResponse }) =>
                    override.destination_ids ?? override.effective_destination_ids ?? [],
            },
        ],
        isOverriding: [
            false,
            {
                setOverriding: (_: boolean, { overriding }: { overriding: boolean }) => overriding,
                loadOverrideSuccess: (_: boolean, { override }: { override: SchemaDestinationsResponse }) =>
                    !override.inherits_from_source,
                saveOverrideSuccess: (_: boolean, { override }: { override: SchemaDestinationsResponse }) =>
                    !override.inherits_from_source,
            },
        ],
    }),
    selectors({
        inheritsFromSource: [
            (s: any) => [s.override],
            (override: SchemaDestinationsResponse) => override.inherits_from_source !== false,
        ],
        // The API rejects an empty set, because with no rows there is nothing to tell it apart
        // from having no override at all, so the table would quietly follow its source again.
        canSave: [
            (s: any) => [s.draftDestinationIds, s.isOverriding],
            (draft: string[], isOverriding: boolean) => isOverriding && draft.length > 0,
        ],
        // Measured against where the table syncs today, inherited or not: either way a destination
        // that is not already receiving this table holds none of its history.
        addedDestinationIds: [
            (s: any) => [s.draftDestinationIds, s.override],
            (draft: string[], override: SchemaDestinationsResponse): string[] => {
                const current = override.destination_ids ?? override.effective_destination_ids ?? []
                return draft.filter((id) => !current.includes(id))
            },
        ],
    }),
    listeners(({ values, actions, props, asyncActions }: any) => ({
        save: () => {
            const added = values.addedDestinationIds
            if (added.length === 0) {
                actions.saveOverride(values.draftDestinationIds)
                return
            }

            const addedNames = values.destinations
                .filter((destination: ExternalDataDestinationApi) => added.includes(destination.id))
                .map((destination: ExternalDataDestinationApi) => destination.name)
                .join(', ')

            LemonDialog.open({
                title: 'Resync to fill in the history?',
                description: `${addedNames} holds none of the data this table has already synced. Saving resyncs the table from scratch so it gets the full history. Every row is read again from the source, and rows bill once per destination, so this bills for every destination this table syncs to.`,
                primaryButton: {
                    children: 'Save and resync',
                    onClick: () => actions.resyncAfterAdding(),
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        // Saved before the resync: a resync against the old set would re-import the table without
        // the destination the user just agreed to pay for.
        resyncAfterAdding: async () => {
            await asyncActions.saveOverride(values.draftDestinationIds)
            try {
                await externalDataSchemasResyncCreate(String(values.currentTeamId), props.schemaId, {})
                lemonToast.success('Resyncing this table')
            } catch {
                lemonToast.error('Could not start a resync for this table')
            }
        },
        clearOverride: () => actions.saveOverride(null),
        saveOverrideSuccess: ({ override }: { override: SchemaDestinationsResponse }) => {
            lemonToast.success(
                override.inherits_from_source
                    ? 'This table follows its source again'
                    : 'Destinations updated for this table'
            )
        },
        saveOverrideFailure: ({ error }: { error: string }) => {
            lemonToast.error(error || 'Could not update destinations')
        },
    })),
    afterMount(({ actions }: any) => {
        actions.loadDestinations()
        actions.loadOverride()
    }),
])
