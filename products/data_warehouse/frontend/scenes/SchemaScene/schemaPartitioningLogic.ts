import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { LemonDialog } from 'lib/lemon-ui/LemonDialog'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import {
    externalDataSchemasPartitioningCreate,
    externalDataSchemasRetrieve,
} from 'products/warehouse_sources/frontend/generated/api'
import {
    PartitionGranularityEnumApi,
    PartitionModeEnumApi,
    SchemaPartitioningApi,
} from 'products/warehouse_sources/frontend/generated/api.schemas'

export interface SchemaPartitioningLogicProps {
    schemaId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface schemaPartitioningLogicValues {
    currentTeamId: number | null // teamLogic
    draftColumn: string | null
    draftGranularity: PartitionGranularityEnumApi
    partitioning: SchemaPartitioningApi | null
    partitioningLoading: boolean
    saveDisabledReason: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface schemaPartitioningLogicActions {
    loadPartitioning: () => any
    loadPartitioningFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadPartitioningSuccess: (
        partitioning: SchemaPartitioningApi,
        payload?: any
    ) => {
        partitioning: SchemaPartitioningApi
        payload?: any
    }
    save: () => {
        value: true
    }
    savePartitioning: () => any
    savePartitioningFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    savePartitioningSuccess: (
        partitioning: SchemaPartitioningApi,
        payload?: any
    ) => {
        partitioning: SchemaPartitioningApi
        payload?: any
    }
    setDraftColumn: (column: string) => {
        column: string
    }
    setDraftGranularity: (granularity: PartitionGranularityEnumApi) => {
        granularity: PartitionGranularityEnumApi
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface schemaPartitioningLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        saveDisabledReason: (partitioning: any, draftColumn: any, draftGranularity: any) => string | null
    }
}

export type schemaPartitioningLogicType = MakeLogicType<
    schemaPartitioningLogicValues,
    schemaPartitioningLogicActions,
    SchemaPartitioningLogicProps,
    schemaPartitioningLogicMeta
>

export const schemaPartitioningLogic = kea<schemaPartitioningLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'scenes', 'SchemaScene', 'schemaPartitioningLogic']),
    props({} as SchemaPartitioningLogicProps),
    key((props: SchemaPartitioningLogicProps) => props.schemaId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        setDraftColumn: (column: string) => ({ column }),
        setDraftGranularity: (granularity: PartitionGranularityEnumApi) => ({ granularity }),
        save: true,
    }),
    loaders(({ values, props }: any) => ({
        partitioning: [
            null as SchemaPartitioningApi | null,
            {
                loadPartitioning: async () =>
                    (await externalDataSchemasRetrieve(String(values.currentTeamId), props.schemaId)).partitioning,
                savePartitioning: async () =>
                    await externalDataSchemasPartitioningCreate(String(values.currentTeamId), props.schemaId, {
                        column: values.draftColumn,
                        date_granularity: values.draftGranularity,
                    }),
            },
        ],
    })),
    reducers({
        draftColumn: [
            null as string | null,
            {
                setDraftColumn: (_: string | null, { column }: { column: string }) => column,
                loadPartitioningSuccess: (
                    state: string | null,
                    { partitioning }: { partitioning: SchemaPartitioningApi }
                ) =>
                    state ??
                    (partitioning.mode === PartitionModeEnumApi.Datetime ? (partitioning.columns[0] ?? null) : null),
            },
        ],
        draftGranularity: [
            PartitionGranularityEnumApi.Day as PartitionGranularityEnumApi,
            {
                setDraftGranularity: (
                    _: PartitionGranularityEnumApi,
                    { granularity }: { granularity: PartitionGranularityEnumApi }
                ) => granularity,
                loadPartitioningSuccess: (
                    state: PartitionGranularityEnumApi,
                    { partitioning }: { partitioning: SchemaPartitioningApi }
                ) => partitioning.date_granularity ?? state,
            },
        ],
    }),
    selectors({
        saveDisabledReason: [
            (s: any) => [s.partitioning, s.draftColumn, s.draftGranularity],
            (
                partitioning: SchemaPartitioningApi | null,
                draftColumn: string | null,
                draftGranularity: PartitionGranularityEnumApi
            ): string | null => {
                if (!partitioning) {
                    return 'Loading'
                }
                if (partitioning.change_pending) {
                    return 'A change is already waiting for the next sync'
                }
                if (!draftColumn) {
                    return 'Choose a column'
                }
                if (
                    partitioning.mode === PartitionModeEnumApi.Datetime &&
                    partitioning.columns[0] === draftColumn &&
                    partitioning.date_granularity === draftGranularity
                ) {
                    return 'The table already uses this partitioning'
                }
                return null
            },
        ],
    }),
    listeners(({ values, actions }: any) => ({
        save: () => {
            LemonDialog.open({
                title: 'Rewrite this table on its next sync?',
                description: `The next sync rewrites the stored files so they are grouped by ${values.draftColumn}. It does not re-import rows from the source, and the rewrite does not count as synced rows. On a large table it can take hours, and the table gets no new data until it finishes.`,
                primaryButton: {
                    children: 'Change partitioning',
                    onClick: () => actions.savePartitioning(),
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        savePartitioningSuccess: () => {
            posthog.capture('warehouse schema partitioning changed', {
                date_granularity: values.draftGranularity,
            })
            lemonToast.success('The next sync will change the partitioning of this table')
        },
        savePartitioningFailure: ({ errorObject }: { errorObject?: { detail?: string | null } }) => {
            lemonToast.error(errorObject?.detail || 'Could not change the partitioning. Try again in a few minutes.')
        },
    })),
    afterMount(({ actions }: any) => {
        actions.loadPartitioning()
    }),
])
