export const RUNNING_POLL_INTERVAL_MS = 10_000
export const HISTORY_PAGE_SIZE = 50

export type HistoryStatusFilter = 'all' | 'FINISHED' | 'FAILED'
export type HistoryRangeFilter = '24h' | '7d' | '30d'

export const HISTORY_RANGE_HOURS: Record<HistoryRangeFilter, number> = { '24h': 24, '7d': 24 * 7, '30d': 24 * 30 }

export interface RunningQueryRow extends TrinoMonitoringQuery {
    loginLabel: string
    canCancel: boolean
}

/** The Trino login the SQL editor uses for this person, in any project of the organization. */
export function isOwnSqlEditorPrincipal(userId: number | null | undefined, principal: string): boolean {
    return userId != null && new RegExp(`^posthog:sql-editor:team:\\d+:user:${userId}$`).test(principal)
}

/** Organization admins may cancel any query. Everyone else may cancel only queries of their own SQL editor login. */
export function canCancelQuery(isAdmin: boolean, userId: number | null | undefined, queryPrincipal: string): boolean {
    return isAdmin || isOwnSqlEditorPrincipal(userId, queryPrincipal)
}

function loginLabelFor(principal: string, userId: number | null | undefined): string {
    if (!principal) {
        return 'Unknown'
    }
    if (isOwnSqlEditorPrincipal(userId, principal)) {
        return 'You'
    }
    return principal.startsWith('posthog:sql-editor:') ? 'SQL editor' : principal
}

function historyWindowStart(range: HistoryRangeFilter): string {
    return dayjs().subtract(HISTORY_RANGE_HOURS[range], 'hour').toISOString()
}

function mergeKnown(
    known: Record<string, string>,
    rows: QueryHistoryRowApi[],
    field: 'source' | 'principal'
): Record<string, string> {
    const next = { ...known }
    for (const row of rows) {
        const key = row[field]
        if (key) {
            next[key] = field === 'source' ? row.source_label : row.principal_label
        }
    }
    return next
}

