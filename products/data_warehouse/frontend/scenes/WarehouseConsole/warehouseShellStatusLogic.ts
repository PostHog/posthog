import { MakeLogicType, afterMount, connect, kea, listeners, path } from 'kea'

import { todayShellLogic } from '~/layout/today/todayShellLogic'

import type { WarehouseStatusResponseApi } from '../../generated/api.schemas'
import { WarehouseConsoleState, warehouseConsoleLogic } from './warehouseConsoleLogic'

/** What the shell needs to know: true once a warehouse exists, false when there is none, null while that is unknown. */
export function warehouseProvisionedFor(consoleState: WarehouseConsoleState): boolean | null {
    switch (consoleState) {
        case 'ready':
        case 'not_ready':
            return true
        case 'no_warehouse':
            return false
        default:
            return null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseShellStatusLogicValues {
    consoleState: WarehouseConsoleState // warehouseConsoleLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseShellStatusLogicActions {
    setWarehouseProvisioned: (provisioned: boolean | null) => {
        provisioned: boolean | null
    } // todayShellLogic
    loadWarehouseStatusFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    } // warehouseConsoleLogic
    loadWarehouseStatusSuccess: (
        warehouseStatus: WarehouseStatusResponseApi | null,
        payload?: any
    ) => {
        payload?: any
        warehouseStatus: WarehouseStatusResponseApi | null
    } // warehouseConsoleLogic
}

export type warehouseShellStatusLogicType = MakeLogicType<
    warehouseShellStatusLogicValues,
    warehouseShellStatusLogicActions
>

/**
 * Reports to the navigation shell whether the organization has a managed warehouse, so the shell can leave out the
 * warehouse sidebar until there is something in it. The shell mounts this only on warehouse pages.
 */
export const warehouseShellStatusLogic = kea<warehouseShellStatusLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'scenes', 'WarehouseConsole', 'warehouseShellStatusLogic']),
    connect(() => ({
        values: [warehouseConsoleLogic, ['consoleState']],
        actions: [
            warehouseConsoleLogic,
            ['loadWarehouseStatusSuccess', 'loadWarehouseStatusFailure'],
            todayShellLogic,
            ['setWarehouseProvisioned'],
        ],
    })),
    listeners(({ actions, values }) => ({
        loadWarehouseStatusSuccess: () => actions.setWarehouseProvisioned(warehouseProvisionedFor(values.consoleState)),
        loadWarehouseStatusFailure: () => actions.setWarehouseProvisioned(warehouseProvisionedFor(values.consoleState)),
    })),
    afterMount(({ actions, values }) => {
        // The status may have loaded before this logic mounted, so report what is already there.
        actions.setWarehouseProvisioned(warehouseProvisionedFor(values.consoleState))
    }),
])
