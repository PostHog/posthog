import { MakeLogicType, afterMount, beforeUnmount, connect, kea, path, reducers, selectors } from 'kea'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import type { FeatureFlagsSet } from 'lib/logic/featureFlagLogic'

import type {
    WarehouseStatusResponseApi,
    WarehouseTrinoConnectionApi,
} from 'products/data_warehouse/frontend/generated/api.schemas'

import { warehouseProvisioningLogic } from '../DataOpsScene/tabs/warehouseProvisioningLogic'

export type WarehouseConsoleState = 'loading' | 'error' | 'no_warehouse' | 'not_ready' | 'ready'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseConsoleLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    initialPassword: string | null // warehouseProvisioningLogic
    isResettingPassword: boolean // warehouseProvisioningLogic
    teamSchemaName: string | null // warehouseProvisioningLogic
    warehouseStatus: WarehouseStatusResponseApi | null // warehouseProvisioningLogic
    warehouseStatusLoading: boolean // warehouseProvisioningLogic
    warehouseStatusResolved: boolean // warehouseProvisioningLogic
    consoleEnabled: boolean
    consoleState: WarehouseConsoleState
    statusFailed: boolean
    trinoConnection: WarehouseTrinoConnectionApi | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseConsoleLogicActions {
    clearInitialPassword: () => {
        value: true
    } // warehouseProvisioningLogic
    loadWarehouseStatus: () => any // warehouseProvisioningLogic
    loadWarehouseStatusFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    } // warehouseProvisioningLogic
    loadWarehouseStatusSuccess: (
        warehouseStatus: WarehouseStatusResponseApi | null,
        payload?: any
    ) => {
        payload?: any
        warehouseStatus: WarehouseStatusResponseApi | null
    } // warehouseProvisioningLogic
    resetPassword: () => {
        value: true
    } // warehouseProvisioningLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseConsoleLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        consoleEnabled: (featureFlags: FeatureFlagsSet) => boolean
        consoleState: (
            warehouseStatus: WarehouseStatusResponseApi | null,
            warehouseStatusResolved: boolean,
            statusFailed: boolean
        ) => WarehouseConsoleState
        trinoConnection: (
            warehouseStatus: WarehouseStatusResponseApi | null,
            consoleState: WarehouseConsoleState
        ) => WarehouseTrinoConnectionApi | null
    }
}

export type warehouseConsoleLogicType = MakeLogicType<
    warehouseConsoleLogicValues,
    warehouseConsoleLogicActions,
    Record<string, any>,
    warehouseConsoleLogicMeta
>

export const warehouseConsoleLogic = kea<warehouseConsoleLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'scenes', 'WarehouseConsole', 'warehouseConsoleLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            warehouseProvisioningLogic,
            [
                'warehouseStatus',
                'warehouseStatusLoading',
                'teamSchemaName',
                'initialPassword',
                'isResettingPassword',
                'warehouseStatusResolved',
            ],
        ],
        actions: [
            warehouseProvisioningLogic,
            [
                'loadWarehouseStatus',
                'loadWarehouseStatusSuccess',
                'loadWarehouseStatusFailure',
                'resetPassword',
                'clearInitialPassword',
            ],
        ],
    })),
    reducers({
        statusFailed: [
            false,
            {
                loadWarehouseStatus: () => false,
                loadWarehouseStatusSuccess: () => false,
                loadWarehouseStatusFailure: () => true,
            },
        ],
    }),
    selectors({
        consoleEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.MANAGED_WAREHOUSE_CONSOLE],
        ],
        // The console works through Trino, so it needs the warehouse and Trino ready, as Data ops does for a Trino organization.
        consoleState: [
            (s) => [s.warehouseStatus, s.warehouseStatusResolved, s.statusFailed],
            (
                warehouseStatus: WarehouseStatusResponseApi | null,
                warehouseStatusResolved: boolean,
                statusFailed: boolean
            ): WarehouseConsoleState => {
                if (!warehouseStatusResolved) {
                    return 'loading'
                }
                if (statusFailed && !warehouseStatus) {
                    return 'error'
                }
                if (!warehouseStatus || warehouseStatus.state === 'deleted') {
                    return 'no_warehouse'
                }
                return warehouseStatus.state === 'ready' && warehouseStatus.trino?.state === 'ready'
                    ? 'ready'
                    : 'not_ready'
            },
        ],
        trinoConnection: [
            (s) => [s.warehouseStatus, s.consoleState],
            (
                warehouseStatus: WarehouseStatusResponseApi | null,
                consoleState: WarehouseConsoleState
            ): WarehouseTrinoConnectionApi | null =>
                consoleState === 'ready' ? (warehouseStatus?.trino?.connection ?? null) : null,
        ],
    }),
    afterMount(({ actions, values }) => {
        // Request the status only when nothing has asked for it yet. The provisioning logic loads it when it mounts first.
        if (!values.warehouseStatusResolved && !values.warehouseStatusLoading) {
            actions.loadWarehouseStatus()
        }
    }),
    beforeUnmount(({ actions }) => {
        // A reset password lives in the shared provisioning logic. It must not outlive the page that showed it.
        actions.clearInitialPassword()
    }),
])
