import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props } from 'kea'
import { router } from 'kea-router'

import { urls } from 'scenes/urls'

import type { WarehouseStatusResponseApi } from '../../generated/api.schemas'
import { WarehouseConsoleState, warehouseConsoleLogic } from './warehouseConsoleLogic'

/**
 * How a page reacts to the warehouse state:
 * - `console`: needs a warehouse, so with none it goes to the upsell page.
 * - `upsell`: the page for organizations without a warehouse, so with one it goes to Usage.
 * - `setup`: the page where the warehouse gets created, so it never redirects.
 */
export type WarehousePageKind = 'console' | 'upsell' | 'setup'

export interface WarehouseConsoleRedirectProps {
    kind: WarehousePageKind
}

/** Where a page of this kind goes for this state, or null to stay. Loading and error never redirect, since they say nothing about whether a warehouse exists. */
export function warehouseConsoleRedirectTarget(
    kind: WarehousePageKind,
    consoleState: WarehouseConsoleState
): string | null {
    if (consoleState === 'no_warehouse') {
        return kind === 'console' ? urls.warehouse() : null
    }
    if (consoleState === 'ready' || consoleState === 'not_ready') {
        return kind === 'upsell' ? urls.warehouseUsage() : null
    }
    return null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseConsoleRedirectLogicValues {
    consoleState: WarehouseConsoleState // warehouseConsoleLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseConsoleRedirectLogicActions {
    loadWarehouseStatusSuccess: (
        warehouseStatus: WarehouseStatusResponseApi | null,
        payload?: any
    ) => {
        payload?: any
        warehouseStatus: WarehouseStatusResponseApi | null
    } // warehouseConsoleLogic
    redirectIfNeeded: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseConsoleRedirectLogicMeta {
    key: WarehousePageKind
}

export type warehouseConsoleRedirectLogicType = MakeLogicType<
    warehouseConsoleRedirectLogicValues,
    warehouseConsoleRedirectLogicActions,
    WarehouseConsoleRedirectProps,
    warehouseConsoleRedirectLogicMeta
>

/** Sends the page to the upsell page, or away from it, once the warehouse status says which one it should show. */
export const warehouseConsoleRedirectLogic = kea<warehouseConsoleRedirectLogicType>([
    props({} as WarehouseConsoleRedirectProps),
    key((props) => props.kind),
    path((key) => [
        'products',
        'data_warehouse',
        'frontend',
        'scenes',
        'WarehouseConsole',
        'warehouseConsoleRedirectLogic',
        key,
    ]),
    connect(() => ({
        values: [warehouseConsoleLogic, ['consoleState']],
        actions: [warehouseConsoleLogic, ['loadWarehouseStatusSuccess']],
    })),
    actions({ redirectIfNeeded: true }),
    listeners(({ actions, values, props }) => ({
        loadWarehouseStatusSuccess: () => actions.redirectIfNeeded(),
        redirectIfNeeded: () => {
            const target = warehouseConsoleRedirectTarget(props.kind, values.consoleState)
            if (target) {
                router.actions.replace(target)
            }
        },
    })),
    afterMount(({ actions }) => {
        // The status may have loaded before this logic mounted.
        actions.redirectIfNeeded()
    }),
])
