export const warehouseAlertNotificationLogic = kea<warehouseAlertNotificationLogicType>([
    props({} as WarehouseAlertNotificationLogicProps),
    key(({ alertId }) => alertId ?? 'new'),
    path((key) => ['products', 'data_warehouse', 'shared', 'alerts', 'warehouseAlertNotificationLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], integrationsLogic, ['integrationsLoading', 'slackIntegrations']],
        actions: [integrationsLogic, ['loadIntegrations', 'loadIntegrationsFailure', 'loadIntegrationsSuccess']],
    })),
    actions({
        addSelectedNotification: true,
        addPendingNotification: (notification: WarehouseAlertCreateDestinationApi) => ({ notification }),
        removePendingNotification: (index: number) => ({ index }),
        setPendingNotifications: (notifications: WarehouseAlertCreateDestinationApi[]) => ({ notifications }),
        createPendingNotifications: (alertId: string) => ({ alertId }),
        setCreatingNotifications: (creatingNotifications: boolean) => ({ creatingNotifications }),
        setSelectedSlackIntegrationId: (integrationId: number | null) => ({ integrationId }),
        deleteDestination: (destination: WarehouseAlertDestinationApi) => ({ destination }),
        setDeletingKey: (deletingKey: string | null) => ({ deletingKey }),
        setSelectedType: (selectedType: WarehouseAlertDestinationTypeEnumApi) => ({ selectedType }),
        setSlackChannelValue: (slackChannelValue: string | null) => ({ slackChannelValue }),
        setWebhookUrl: (webhookUrl: string) => ({ webhookUrl }),
        setPagerDutyRoutingKey: (pagerDutyRoutingKey: string) => ({ pagerDutyRoutingKey }),
        setPagerDutySeverity: (pagerDutySeverity: AlertPagerDutySeverity) => ({ pagerDutySeverity }),
        setPagerDutyRegion: (pagerDutyRegion: AlertPagerDutyRegion) => ({ pagerDutyRegion }),
    }),
    loaders(({ props, values }) => ({
        destinations: [
            null as WarehouseAlertDestinationApi[] | null,
            {
                loadDestinations: async () =>
                    props.alertId
                        ? await warehouseAlertsDestinationsList(String(values.currentTeamId), props.alertId)
                        : [],
            },
        ],
    })),
    reducers({
        pendingNotifications: [
            [] as WarehouseAlertCreateDestinationApi[],
            {
                addPendingNotification: (state, { notification }) => [...state, notification],
                removePendingNotification: (state, { index }) => state.filter((_, i) => i !== index),
                setPendingNotifications: (_, { notifications }) => notifications,
            },
        ],
        creatingNotifications: [
            false,
            { setCreatingNotifications: (_, { creatingNotifications }) => creatingNotifications },
        ],
        selectedSlackIntegrationId: [
            null as number | null,
            { setSelectedSlackIntegrationId: (_, { integrationId }) => integrationId },
        ],
        destinationsFailed: [
            false,
            {
                loadDestinations: () => false,
                loadDestinationsFailure: () => true,
            },
        ],
        deletingKey: [
            null as string | null,
            {
                setDeletingKey: (_, { deletingKey }) => deletingKey,
            },
        ],
        integrationsFailed: [
            false,
            {
                loadIntegrations: () => false,
                loadIntegrationsFailure: () => true,
                loadIntegrationsSuccess: () => false,
            },
        ],
        selectedType: [
            WarehouseAlertDestinationTypeEnumApi.Slack as WarehouseAlertDestinationTypeEnumApi,
            { setSelectedType: (_, { selectedType }) => selectedType },
        ],
        slackChannelValue: [
            null as string | null,
            {
                setSlackChannelValue: (_, { slackChannelValue }) => slackChannelValue,
                // A channel picked in one workspace means nothing in another.
                setSelectedSlackIntegrationId: () => null,
            },
        ],
        webhookUrl: ['', { setWebhookUrl: (_, { webhookUrl }) => webhookUrl }],
        pagerDutyRoutingKey: ['', { setPagerDutyRoutingKey: (_, { pagerDutyRoutingKey }) => pagerDutyRoutingKey }],
        pagerDutySeverity: [
            'critical' as AlertPagerDutySeverity,
            { setPagerDutySeverity: (_, { pagerDutySeverity }) => pagerDutySeverity },
        ],
        pagerDutyRegion: [
            'us' as AlertPagerDutyRegion,
            { setPagerDutyRegion: (_, { pagerDutyRegion }) => pagerDutyRegion },
        ],
    }),
    selectors({
        selectedSlackIntegration: [
            (s) => [s.slackIntegrations, s.selectedSlackIntegrationId],
            (
                slackIntegrations: IntegrationType[] | undefined,
                selectedSlackIntegrationId: number | null
            ): IntegrationType | undefined =>
                slackIntegrations?.find((integration) => integration.id === selectedSlackIntegrationId) ??
                slackIntegrations?.[0],
        ],
        selectedNotification: [
            (s) => [
                s.selectedType,
                s.selectedSlackIntegration,
                s.slackChannelValue,
                s.webhookUrl,
                s.pagerDutyRoutingKey,
                s.pagerDutySeverity,
                s.pagerDutyRegion,
            ],
            (
                selectedType: WarehouseAlertDestinationTypeEnumApi,
                selectedSlackIntegration: IntegrationType | undefined,
                slackChannelValue: string | null,
                webhookUrl: string,
                pagerDutyRoutingKey: string,
                pagerDutySeverity: AlertPagerDutySeverity,
                pagerDutyRegion: AlertPagerDutyRegion
            ): WarehouseAlertCreateDestinationApi | null => {
                if (selectedType === WarehouseAlertDestinationTypeEnumApi.Slack) {
                    if (!selectedSlackIntegration || !slackChannelValue) {
                        return null
                    }
                    // The channel picker's value is "<channel id>|#<channel name>".
                    const [channelId, channelLabel] = slackChannelValue.split('|')
                    return {
                        type: selectedType,
                        slack_workspace_id: selectedSlackIntegration.id,
                        slack_channel_id: channelId,
                        slack_channel_name: channelLabel?.replace('#', '') || channelId,
                    }
                }
                if (selectedType === WarehouseAlertDestinationTypeEnumApi.Pagerduty) {
                    return {
                        type: selectedType,
                        pagerduty_routing_key: pagerDutyRoutingKey.trim(),
                        pagerduty_severity: pagerDutySeverity,
                        pagerduty_region: pagerDutyRegion,
                    }
                }
                return { type: selectedType, webhook_url: webhookUrl.trim() }
            },
        ],
        addDisabledReason: [
            (s) => [
                s.selectedType,
                s.selectedSlackIntegration,
                s.slackChannelValue,
                s.webhookUrl,
                s.pagerDutyRoutingKey,
                s.creatingNotifications,
                s.destinations,
                s.pendingNotifications,
                s.selectedNotification,
            ],
            (
                selectedType: WarehouseAlertDestinationTypeEnumApi,
                selectedSlackIntegration: IntegrationType | undefined,
                slackChannelValue: string | null,
                webhookUrl: string,
                pagerDutyRoutingKey: string,
                creatingNotifications: boolean,
                destinations: WarehouseAlertDestinationApi[] | null,
                pendingNotifications: WarehouseAlertCreateDestinationApi[],
                selectedNotification: WarehouseAlertCreateDestinationApi | null
            ): string | undefined => {
                if (creatingNotifications) {
                    return 'Saving the destinations you added'
                }
                if ((destinations?.length ?? 0) + pendingNotifications.length >= MAX_DESTINATIONS_PER_ALERT) {
                    return `An alert can have at most ${MAX_DESTINATIONS_PER_ALERT} destinations`
                }
                // Saved webhook and PagerDuty destinations come back redacted, so only a Slack channel
                // can be matched against them.
                const alreadyAdded =
                    selectedNotification &&
                    (pendingNotifications.some((pending) => isSameNotification(pending, selectedNotification)) ||
                        (destinations ?? []).some(
                            (destination) =>
                                destination.type === WarehouseAlertDestinationTypeEnumApi.Slack &&
                                isSameNotification(destination, selectedNotification)
                        ))
                if (alreadyAdded) {
                    return 'This alert already sends to this destination'
                }
                if (selectedType === WarehouseAlertDestinationTypeEnumApi.Slack) {
                    if (!selectedSlackIntegration) {
                        return 'Connect Slack first'
                    }
                    return slackChannelValue ? undefined : 'Select a Slack channel'
                }
                if (selectedType === WarehouseAlertDestinationTypeEnumApi.Pagerduty) {
                    if (!pagerDutyRoutingKey.trim()) {
                        return 'Enter the PagerDuty integration key'
                    }
                    return PAGERDUTY_ROUTING_KEY_PATTERN.test(pagerDutyRoutingKey.trim())
                        ? undefined
                        : 'The integration key is 32 letters and digits'
                }
                return webhookUrl.trim() ? undefined : 'Enter a webhook URL'
            },
        ],
    }),
    listeners(({ actions, values, props }) => ({
        addSelectedNotification: () => {
            const notification = values.selectedNotification
            if (values.addDisabledReason || !notification) {
                return
            }
            actions.addPendingNotification(notification)
            if (notification.type === WarehouseAlertDestinationTypeEnumApi.Slack) {
                actions.setSlackChannelValue(null)
            } else if (notification.type === WarehouseAlertDestinationTypeEnumApi.Pagerduty) {
                actions.setPagerDutyRoutingKey('')
            } else {
                actions.setWebhookUrl('')
            }
        },
        addPendingNotification: () => {
            // A saved alert takes the destination at once. A new one keeps it until the alert exists.
            if (props.alertId) {
                actions.createPendingNotifications(props.alertId)
            }
        },
        loadIntegrationsSuccess: () => {
            if (
                !values.selectedSlackIntegration &&
                values.selectedType === WarehouseAlertDestinationTypeEnumApi.Slack
            ) {
                actions.setSelectedType(WarehouseAlertDestinationTypeEnumApi.Webhook)
            }
        },
        createPendingNotifications: async ({ alertId }) => {
            const pending = values.pendingNotifications
            if (pending.length === 0) {
                return
            }
            const projectId = String(values.currentTeamId)
            // Add stays disabled until these settle, so a second add can't send the same destination twice.
            actions.setCreatingNotifications(true)
            const results = await Promise.allSettled(
                pending.map((notification) => warehouseAlertsDestinationsCreate(projectId, alertId, notification))
            )
            actions.setCreatingNotifications(false)
            pending
                .filter((_, index) => results[index].status === 'fulfilled')
                .forEach((notification) =>
                    posthog.capture('warehouse alert notification added', { type: notification.type })
                )
            const failedCount = results.filter((result) => result.status === 'rejected').length
            const refusals = [
                ...new Set(results.map(refusalDetail).filter((detail): detail is string => detail !== undefined)),
            ]
            // A refused destination fails the same way on every retry, so only the others stay to send again.
            actions.setPendingNotifications(
                pending.filter((_, index) => results[index].status === 'rejected' && !refusalDetail(results[index]))
            )
            if (failedCount > 0) {
                const summary = `Couldn't add ${failedCount} notification destination${failedCount === 1 ? '' : 's'}.`
                lemonToast.error(
                    refusals.length > 0
                        ? `${summary} ${refusals.join(' ')}`
                        : `${summary} Open the alert and add ${failedCount === 1 ? 'it' : 'them'} again.`
                )
            }
            if (props.alertId) {
                actions.loadDestinations()
            }
        },
        deleteDestination: async ({ destination }) => {
            if (!props.alertId) {
                return
            }
            const { title } = describeNotification(destination)
            actions.setDeletingKey(destinationKey(destination))
            try {
                await warehouseAlertsDestinationsDeleteCreate(String(values.currentTeamId), props.alertId, {
                    destination_ids: [destination.id],
                })
                posthog.capture('warehouse alert notification removed', { type: destination.type })
                lemonToast.success(`Removed the ${title} destination`)
            } catch {
                lemonToast.error(`Couldn't remove the ${title} destination. Try again in a moment.`)
            } finally {
                actions.setDeletingKey(null)
                actions.loadDestinations()
            }
        },
    })),
    afterMount(({ actions, props }) => {
        if (props.alertId) {
            actions.loadDestinations()
        }
    }),
])
