export const destinationKey = (destination: WarehouseAlertDestinationApi): string => destination.id

/** The message the API gave for a refused destination, such as the per-alert cap or a duplicate. */
function refusalDetail(result: PromiseSettledResult<unknown>): string | undefined {
    if (result.status === 'fulfilled') {
        return undefined
    }
    const detail = (result.reason as { detail?: unknown } | undefined)?.detail
    return typeof detail === 'string' && detail ? detail : undefined
}

type NotificationTarget = Pick<
    WarehouseAlertCreateDestinationApi,
    'type' | 'slack_workspace_id' | 'slack_channel_id' | 'webhook_url' | 'pagerduty_routing_key'
>

function isSameNotification(a: NotificationTarget, b: NotificationTarget): boolean {
    if (a.type !== b.type) {
        return false
    }
    if (a.type === WarehouseAlertDestinationTypeEnumApi.Slack) {
        return a.slack_workspace_id === b.slack_workspace_id && a.slack_channel_id === b.slack_channel_id
    }
    if (a.type === WarehouseAlertDestinationTypeEnumApi.Pagerduty) {
        return a.pagerduty_routing_key === b.pagerduty_routing_key
    }
    return a.webhook_url === b.webhook_url
}

