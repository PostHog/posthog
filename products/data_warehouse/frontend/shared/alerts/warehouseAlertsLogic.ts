import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { PaginatedResponse } from 'lib/api'
import { LemonDialog } from 'lib/lemon-ui/LemonDialog'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import { ExternalDataSource } from '~/types'

import { platformAlertsDestroy, platformAlertsList } from 'products/alerts_platform/frontend/generated/api'
import {
    PlatformAlertConfigurationApi,
    PlatformAlertConfigurationSourceKindEnumApi,
} from 'products/alerts_platform/frontend/generated/api.schemas'
import { ExternalDataDestinationApi } from 'products/warehouse_sources/frontend/generated/api.schemas'

import { destinationLookupLogic } from '../logics/destinationLookupLogic'
import { sourcesDataLogic } from '../logics/sourcesDataLogic'
import { WarehouseAlertKind, alertsForScope } from './warehouseAlertConfig'

export interface WarehouseAlertTargetOption {
    id: string
    label: string
}

// The list endpoint has no source kind filter, so the logic reads every page and filters here.
const PAGE_SIZE = 100

export interface WarehouseAlertsLogicProps {
    kind: WarehouseAlertKind
    /** Show only the alerts that watch this source or destination. Unset shows every alert of the kind. */
    targetId?: string
}

export const warehouseAlertsLogicKey = ({ kind, targetId }: WarehouseAlertsLogicProps): string =>
    `${kind}/${targetId ?? 'all'}`

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseAlertsLogicValues {
    destinations: ExternalDataDestinationApi[] // destinationLookupLogic
    dataWarehouseSources: PaginatedResponse<ExternalDataSource> | null // sourcesDataLogic
    currentTeamId: number | null // teamLogic
    alerts: PlatformAlertConfigurationApi[] | null
    alertsFailed: boolean
    alertsLoading: boolean
    deletingAlertId: string | null
    targetLabels: Record<string, string>
    targetOptions: WarehouseAlertTargetOption[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseAlertsLogicActions {
    loadDestinations: () => any // destinationLookupLogic
    loadSources: () => {
        value: true
    } // sourcesDataLogic
    deleteAlert: (alert: PlatformAlertConfigurationApi) => {
        alert: PlatformAlertConfigurationApi
    }
    loadAlerts: (_: any) => any
    loadAlertsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAlertsSuccess: (
        alerts: PlatformAlertConfigurationApi[],
        payload?: any
    ) => {
        alerts: PlatformAlertConfigurationApi[]
        payload?: any
    }
    setDeletingAlertId: (deletingAlertId: string | null) => {
        deletingAlertId: string | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface warehouseAlertsLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        targetOptions: (dataWarehouseSources: any, destinations: any, arg: any) => WarehouseAlertTargetOption[]
        targetLabels: (targetOptions: any) => Record<string, string>
    }
}

export type warehouseAlertsLogicType = MakeLogicType<
    warehouseAlertsLogicValues,
    warehouseAlertsLogicActions,
    WarehouseAlertsLogicProps,
    warehouseAlertsLogicMeta
>

export const warehouseAlertsLogic = kea<warehouseAlertsLogicType>([
    props({} as WarehouseAlertsLogicProps),
    key(warehouseAlertsLogicKey),
    path((key) => ['products', 'data_warehouse', 'shared', 'alerts', 'warehouseAlertsLogic', key]),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            sourcesDataLogic,
            ['dataWarehouseSources'],
            destinationLookupLogic,
            ['destinations'],
        ],
        actions: [sourcesDataLogic, ['loadSources'], destinationLookupLogic, ['loadDestinations']],
    })),
    actions({
        deleteAlert: (alert: PlatformAlertConfigurationApi) => ({ alert }),
        setDeletingAlertId: (deletingAlertId: string | null) => ({ deletingAlertId }),
    }),
    loaders(({ props, values }) => ({
        alerts: [
            null as PlatformAlertConfigurationApi[] | null,
            {
                loadAlerts: async (_, breakpoint) => {
                    const projectId = String(values.currentTeamId)
                    const results: PlatformAlertConfigurationApi[] = []
                    let offset = 0
                    while (true) {
                        const page = await platformAlertsList(projectId, { limit: PAGE_SIZE, offset })
                        breakpoint()
                        results.push(...page.results)
                        offset += page.results.length
                        if (!page.next || page.results.length === 0) {
                            break
                        }
                    }
                    return alertsForScope(results, props.kind, props.targetId)
                },
            },
        ],
    })),
    reducers({
        alertsFailed: [
            false,
            {
                loadAlerts: () => false,
                loadAlertsSuccess: () => false,
                loadAlertsFailure: () => true,
            },
        ],
        deletingAlertId: [
            null as string | null,
            {
                setDeletingAlertId: (_, { deletingAlertId }) => deletingAlertId,
            },
        ],
    }),
    selectors({
        // What an alert of this kind can watch. Direct connect sources never sync, and the PostHog
        // warehouse is written by the sync itself, so neither can fail the way an alert checks for.
        targetOptions: [
            (s) => [s.dataWarehouseSources, s.destinations, (_, props) => props.kind],
            (
                sources: PaginatedResponse<ExternalDataSource> | null,
                destinations: ExternalDataDestinationApi[],
                kind: WarehouseAlertKind
            ): WarehouseAlertTargetOption[] =>
                kind === PlatformAlertConfigurationSourceKindEnumApi.WarehouseSource
                    ? (sources?.results ?? [])
                          .filter((source) => source.access_method !== 'direct')
                          .map((source) => ({
                              id: source.id,
                              label: source.prefix ? `${source.source_type} (${source.prefix})` : source.source_type,
                          }))
                    : destinations
                          .filter((destination) => !destination.is_posthog_warehouse)
                          .map((destination) => ({ id: destination.id, label: destination.name })),
        ],
        targetLabels: [
            (s) => [s.targetOptions],
            (options: WarehouseAlertTargetOption[]): Record<string, string> =>
                Object.fromEntries(options.map((option) => [option.id, option.label])),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        deleteAlert: ({ alert }) => {
            LemonDialog.open({
                title: `Delete ${alert.name}?`,
                description: 'The alert stops checking, and its notification destinations are removed with it.',
                primaryButton: {
                    children: 'Delete alert',
                    status: 'danger',
                    'data-attr': 'warehouse-alert-delete-confirm',
                    onClick: async () => {
                        actions.setDeletingAlertId(alert.id)
                        try {
                            await platformAlertsDestroy(String(values.currentTeamId), alert.id)
                            posthog.capture('warehouse alert deleted', { kind: props.kind })
                            lemonToast.success(`Deleted ${alert.name}`)
                        } catch {
                            lemonToast.error(`Couldn't delete ${alert.name}. Try again in a moment.`)
                        } finally {
                            actions.setDeletingAlertId(null)
                            actions.loadAlerts()
                        }
                    },
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
    })),
    afterMount(({ actions, values, props }) => {
        actions.loadAlerts()
        if (props.kind === PlatformAlertConfigurationSourceKindEnumApi.WarehouseSource) {
            if (!values.dataWarehouseSources) {
                actions.loadSources()
            }
        } else if (values.destinations.length === 0) {
            actions.loadDestinations()
        }
    }),
])
