const REFRESH_INTERVAL = 10000
const IDLE_REFRESH_INTERVAL = 15000
const SOURCE_SUMMARY_PATHS = ['/data-management/sources', '/data-management/revenue']

export const shouldLoadSourceSummaries = (pathname: string): boolean =>
    SOURCE_SUMMARY_PATHS.some((path) => pathname.endsWith(path))

export const areSourceSummariesActivelySyncing = (
    summaries: PaginatedExternalDataSourceSummaryListApi | null
): boolean =>
    (summaries?.results ?? []).some(
        (source) =>
            source.status === ExternalDataJobStatus.Running ||
            (source.schema_status_names[ExternalDataSchemaStatus.Running]?.length ?? 0) > 0
    )

