export const sourceSummariesLogic = kea<sourceSummariesLogicType>([
    path(['products', 'dataWarehouse', 'sourceSummariesLogic']),
    connect(() => ({
        values: [availableSourcesLogic, ['availableSources']],
    })),
    actions({
        abortAnyRunningQuery: true,
        loadSourceSummaries: true,
        deleteSource: (source: ExternalDataSourceSummaryApi) => ({ source }),
        reloadSource: (source: ExternalDataSourceSummaryApi) => ({ source }),
        sourceLoadingFinished: (source: ExternalDataSourceSummaryApi) => ({ source }),
        setDirectSearchTerm: (directSearchTerm: string) => ({ directSearchTerm }),
        setManagedSearchTerm: (managedSearchTerm: string) => ({ managedSearchTerm }),
    }),
    loaders(({ actions, cache, values }) => ({
        sourceSummaries: [
            null as PaginatedExternalDataSourceSummaryListApi | null,
            {
                loadSourceSummaries: async (_, breakpoint): Promise<PaginatedExternalDataSourceSummaryListApi> => {
                    await breakpoint(300)
                    actions.abortAnyRunningQuery()

                    cache.abortController = new AbortController()
                    const methodOptions: ApiMethodOptions = { signal: cache.abortController.signal }
                    try {
                        const summaries = await api.externalDataSources.listSummaries(methodOptions)
                        breakpoint()
                        cache.abortController = null
                        return summaries
                    } catch (error: unknown) {
                        const apiError = error as { status?: number; name?: string }
                        const isTransient =
                            apiError.status === 403 ||
                            apiError.name === 'AbortError' ||
                            (error instanceof ApiError && error.status === undefined)
                        if (!isTransient) {
                            throw error
                        }
                        breakpoint()
                        cache.abortController = null
                        return { results: [], count: 0, next: null, previous: null }
                    }
                },
                updateSourceRevenueAnalyticsConfig: async ({
                    source,
                    config,
                }: {
                    source: ExternalDataSourceSummaryApi
                    config: Partial<ExternalDataSourceRevenueAnalyticsConfig>
                }): Promise<PaginatedExternalDataSourceSummaryListApi> => {
                    const updatedSource = await api.externalDataSources.updateRevenueAnalyticsConfig(source.id, config)
                    return {
                        count: values.sourceSummaries?.count ?? 0,
                        next: values.sourceSummaries?.next,
                        previous: values.sourceSummaries?.previous,
                        results:
                            values.sourceSummaries?.results.map((currentSource) =>
                                currentSource.id === updatedSource.id
                                    ? {
                                          ...currentSource,
                                          revenue_analytics_config: updatedSource.revenue_analytics_config,
                                      }
                                    : currentSource
                            ) ?? [],
                    }
                },
            },
        ],
    })),
    reducers(() => ({
        directSearchTerm: [
            '' as string,
            {
                setDirectSearchTerm: (_, { directSearchTerm }) => directSearchTerm,
            },
        ],
        managedSearchTerm: [
            '' as string,
            {
                setManagedSearchTerm: (_, { managedSearchTerm }) => managedSearchTerm,
            },
        ],
        sourceReloadingById: [
            {} as Record<string, boolean>,
            {
                reloadSource: (state, { source }) => ({ ...state, [source.id]: true }),
                deleteSource: (state, { source }) => ({ ...state, [source.id]: true }),
                sourceLoadingFinished: (state, { source }) => ({ ...state, [source.id]: false }),
            },
        ],
    })),
    selectors({
        managedSourceSummaries: [
            (s) => [s.sourceSummaries],
            (sourceSummaries: PaginatedExternalDataSourceSummaryListApi | null): ExternalDataSourceSummaryApi[] =>
                (sourceSummaries?.results ?? []).filter((source) => source.access_method !== 'direct'),
        ],
        directSourceSummaries: [
            (s) => [s.sourceSummaries],
            (sourceSummaries: PaginatedExternalDataSourceSummaryListApi | null): ExternalDataSourceSummaryApi[] =>
                (sourceSummaries?.results ?? []).filter((source) => source.access_method === 'direct'),
        ],
        managedSourceSummariesFuse: [
            (s) => [s.managedSourceSummaries, s.availableSources],
            (
                managedSourceSummaries: ExternalDataSourceSummaryApi[],
                availableSources: Record<string, SourceConfig> | null
            ): Fuse<ExternalDataSourceSummaryApi> =>
                createFuse(managedSourceSummaries, {
                    keys: [
                        {
                            name: 'label',
                            getFn: (source) => availableSources?.[source.source_type]?.label ?? source.source_type,
                        },
                        'source_type',
                        'prefix',
                        'description',
                    ],
                }),
        ],
        filteredManagedSourceSummaries: [
            (s) => [s.managedSourceSummaries, s.managedSourceSummariesFuse, s.managedSearchTerm],
            (
                managedSourceSummaries: ExternalDataSourceSummaryApi[],
                managedSourceSummariesFuse: Fuse<ExternalDataSourceSummaryApi>,
                managedSearchTerm: string
            ): ExternalDataSourceSummaryApi[] => {
                const trimmedSearchTerm = managedSearchTerm.trim()
                return trimmedSearchTerm
                    ? managedSourceSummariesFuse.search(trimmedSearchTerm).map(({ item }) => item)
                    : managedSourceSummaries
            },
        ],
        filteredDirectSourceSummaries: [
            (s) => [s.directSourceSummaries, s.directSearchTerm],
            (
                directSourceSummaries: ExternalDataSourceSummaryApi[],
                directSearchTerm: string
            ): ExternalDataSourceSummaryApi[] => {
                const normalizedSearchTerm = directSearchTerm.trim().toLowerCase()
                if (!normalizedSearchTerm) {
                    return directSourceSummaries
                }
                return directSourceSummaries.filter(
                    (source) =>
                        source.source_type.toLowerCase().includes(normalizedSearchTerm) ||
                        source.prefix?.toLowerCase().includes(normalizedSearchTerm) ||
                        source.description?.toLowerCase().includes(normalizedSearchTerm)
                )
            },
        ],
    }),
    listeners(({ actions, cache, values }) => ({
        abortAnyRunningQuery: () => {
            if (cache.abortController) {
                cache.abortController.abort()
                cache.abortController = null
            }
        },
        deleteSource: async ({ source }) => {
            await api.externalDataSources.delete(source.id)
            actions.loadSourceSummaries()
            actions.sourceLoadingFinished(source)
            posthog.capture('source deleted', { sourceType: source.source_type })
        },
        reloadSource: async ({ source }) => {
            if (values.sourceSummaries) {
                actions.loadSourceSummariesSuccess({
                    ...values.sourceSummaries,
                    results: values.sourceSummaries.results.map((currentSource) =>
                        currentSource.id === source.id
                            ? { ...currentSource, status: ExternalDataJobStatus.Running }
                            : currentSource
                    ),
                })
            }
            try {
                await api.externalDataSources.reload(source.id)
                actions.loadSourceSummaries()
                posthog.capture('source reloaded', { sourceType: source.source_type })
            } catch (error: unknown) {
                const message = error instanceof Error ? error.message : null
                lemonToast.error(message || 'Cant refresh source at this time')
            }
            actions.sourceLoadingFinished(source)
        },
        loadSourceSummariesSuccess: ({ sourceSummaries }) => {
            if (!shouldLoadSourceSummaries(router.values.location.pathname)) {
                return
            }
            const interval = areSourceSummariesActivelySyncing(sourceSummaries)
                ? REFRESH_INTERVAL
                : IDLE_REFRESH_INTERVAL
            cache.disposables.add(() => {
                const timerId = setTimeout(() => {
                    if (shouldLoadSourceSummaries(router.values.location.pathname)) {
                        actions.loadSourceSummaries()
                    }
                }, interval)
                return () => clearTimeout(timerId)
            }, 'refreshTimeout')
        },
        loadSourceSummariesFailure: () => {
            if (!shouldLoadSourceSummaries(router.values.location.pathname)) {
                return
            }
            cache.disposables.add(() => {
                const timerId = setTimeout(() => {
                    if (shouldLoadSourceSummaries(router.values.location.pathname)) {
                        actions.loadSourceSummaries()
                    }
                }, IDLE_REFRESH_INTERVAL)
                return () => clearTimeout(timerId)
            }, 'refreshTimeout')
        },
    })),
    urlToAction(({ actions }) =>
        Object.fromEntries(
            SOURCE_SUMMARY_PATHS.map((sourcePath) => [
                sourcePath,
                (
                    _params: Record<string, string | undefined>,
                    _searchParams: Record<string, unknown>,
                    _hashParams: Record<string, unknown>,
                    currentLocation: { pathname: string; initial?: boolean },
                    previousLocation?: { pathname: string }
                ): void => {
                    if (!currentLocation.initial && currentLocation.pathname !== previousLocation?.pathname) {
                        actions.loadSourceSummaries()
                    }
                },
            ])
        )
    ),
    afterMount(({ actions }) => {
        actions.loadSourceSummaries()
    }),
    beforeUnmount(() => {
        // Disposables plugin handles cleanup automatically.
    }),
])
