import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { billingLogic } from 'scenes/billing/billingLogic'
import { teamLogic } from 'scenes/teamLogic'

import { BillingType, ExternalDataSource } from '~/types'

import { dataWarehouseTotalRowsStatsRetrieve } from 'products/data_warehouse/frontend/generated/api'
import type { PipelineRowsStatsResponseApi } from 'products/data_warehouse/frontend/generated/api.schemas'

import { estimateSourceCostsUsd } from '../sourceUsageCost'
import { sourceManagementLogic } from './sourceManagementLogic'
import { sourcesDataLogic } from './sourcesDataLogic'

const SYNCED_ROWS_BILLING_PRODUCT = 'data_warehouse'

export interface SourceUsage {
    billableRows: number
    costUsd: number | null
}

