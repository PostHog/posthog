export type sourceUsageLogicType = MakeLogicType<
    sourceUsageLogicValues,
    sourceUsageLogicActions,
    Record<string, any>,
    sourceUsageLogicMeta
>

export const sourceUsageLogic = kea<sourceUsageLogicType>([
    path(['products', 'dataWarehouse', 'sourceUsageLogic']),
    connect(() => ({
        values: [
            billingLogic,
            ['billing'],
            featureFlagLogic,
            ['featureFlags'],
            sourceManagementLogic,
            ['managedSources'],
            teamLogic,
            ['currentTeamId'],
        ],
        actions: [
            billingLogic,
            ['loadBilling', 'loadBillingSuccess'],
            featureFlagLogic,
            ['setFeatureFlags'],
            sourcesDataLogic,
            ['loadSourcesSuccess'],
        ],
    })),
    actions({
        loadUsageIfShown: true,
    }),
    reducers({
        // Set on the first request and never reset, so a failed load is not retried on every sources poll.
        billingRequested: [false, { loadBilling: () => true }],
        rowsStatsRequested: [false, { loadRowsStats: () => true }],
    }),
    loaders(({ values }) => ({
        rowsStats: [
            null as PipelineRowsStatsResponseApi | null,
            {
                loadRowsStats: async () => {
                    try {
                        return await dataWarehouseTotalRowsStatsRetrieve(String(values.currentTeamId))
                    } catch {
                        // The endpoint fails when billing can't be reached. The table then shows no usage
                        // rather than an error, since usage is extra context next to each source.
                        return null
                    }
                },
            },
        ],
    })),
    selectors({
        syncedRowsProduct: [
            (s) => [s.billing],
            (billing: BillingType | null): BillingProductV2Type | null =>
                billing?.products?.find((product) => product.type === SYNCED_ROWS_BILLING_PRODUCT) ?? null,
        ],
        showUsageColumns: [
            (s) => [s.managedSources, s.syncedRowsProduct, s.featureFlags],
            (
                managedSources: ExternalDataSource[],
                syncedRowsProduct: BillingProductV2Type | null,
                featureFlags: FeatureFlagsSet
            ): boolean =>
                // Reading the flag sends the experiment exposure, so only read it for orgs that would see the columns.
                managedSources.length > 0 &&
                !!syncedRowsProduct &&
                featureFlags[FEATURE_FLAGS.DWH_SOURCE_COST_COLUMNS] === 'test',
        ],
        sourceUsageById: [
            (s) => [s.rowsStats, s.syncedRowsProduct],
            (
                rowsStats: PipelineRowsStatsResponseApi | null,
                syncedRowsProduct: BillingProductV2Type | null
            ): Record<string, SourceUsage> | null => {
                if (!rowsStats?.billing_available) {
                    return null
                }
                const billableRows = rowsStats.billable_rows_by_source
                const costs = estimateSourceCostsUsd(billableRows, syncedRowsProduct)
                return Object.fromEntries(
                    Object.entries(billableRows).map(([sourceId, rows]) => [
                        sourceId,
                        { billableRows: rows, costUsd: costs?.[sourceId] ?? null },
                    ])
                )
            },
        ],
        showSourceCost: [
            (s) => [s.sourceUsageById],
            (sourceUsageById: Record<string, SourceUsage> | null): boolean =>
                !!sourceUsageById && Object.values(sourceUsageById).some((usage) => usage.costUsd !== null),
        ],
    }),
    listeners(({ actions, values }) => ({
        loadUsageIfShown: () => {
            if (values.managedSources.length === 0) {
                return
            }
            // billingLogic doesn't load on mount. Both arms load it, because the exposure waits for the billing product.
            if (!values.billing && !values.billingRequested) {
                actions.loadBilling()
            }
            if (values.showUsageColumns && !values.rowsStatsRequested) {
                actions.loadRowsStats()
            }
        },
        loadBillingSuccess: () => actions.loadUsageIfShown(),
        loadSourcesSuccess: () => actions.loadUsageIfShown(),
        setFeatureFlags: () => actions.loadUsageIfShown(),
    })),
    afterMount(({ actions }) => {
        actions.loadUsageIfShown()
    }),
])
