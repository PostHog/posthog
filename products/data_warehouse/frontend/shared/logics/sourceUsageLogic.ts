import { MakeLogicType, afterMount, connect, kea, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { billingLogic } from 'scenes/billing/billingLogic'
import { teamLogic } from 'scenes/teamLogic'

import { BillingType } from '~/types'

import { dataWarehouseTotalRowsStatsRetrieve } from 'products/data_warehouse/frontend/generated/api'
import type { PipelineRowsStatsResponseApi } from 'products/data_warehouse/frontend/generated/api.schemas'

import { estimateSourceCostsUsd } from '../sourceUsageCost'

const SYNCED_ROWS_BILLING_PRODUCT = 'data_warehouse'

export interface SourceUsage {
    billableRows: number
    costUsd: number | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sourceUsageLogicValues {
    billing: BillingType | null // billingLogic
    currentTeamId: number | null // teamLogic
    rowsStats: PipelineRowsStatsResponseApi | null
    rowsStatsLoading: boolean
    showSourceCost: boolean
    sourceUsageById: Record<string, SourceUsage> | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sourceUsageLogicActions {
    loadBilling: () => any // billingLogic
    loadRowsStats: () => any
    loadRowsStatsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRowsStatsSuccess: (
        rowsStats: PipelineRowsStatsResponseApi | null,
        payload?: any
    ) => {
        rowsStats: PipelineRowsStatsResponseApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sourceUsageLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        sourceUsageById: (
            rowsStats: PipelineRowsStatsResponseApi | null,
            billing: BillingType | null
        ) => Record<string, SourceUsage> | null
        showSourceCost: (sourceUsageById: Record<string, SourceUsage> | null) => boolean
    }
}

export type sourceUsageLogicType = MakeLogicType<
    sourceUsageLogicValues,
    sourceUsageLogicActions,
    Record<string, any>,
    sourceUsageLogicMeta
>

export const sourceUsageLogic = kea<sourceUsageLogicType>([
    path(['products', 'dataWarehouse', 'sourceUsageLogic']),
    connect(() => ({
        values: [billingLogic, ['billing'], teamLogic, ['currentTeamId']],
        actions: [billingLogic, ['loadBilling']],
    })),
    loaders(({ values }) => ({
        rowsStats: [
            null as PipelineRowsStatsResponseApi | null,
            {
                loadRowsStats: async () => {
                    try {
                        return await dataWarehouseTotalRowsStatsRetrieve(String(values.currentTeamId))
                    } catch {
                        // The endpoint fails when billing can't be reached. The table then shows no usage
                        // rather than an error, since usage is extra context next to each source.
                        return null
                    }
                },
            },
        ],
    })),
    selectors({
        sourceUsageById: [
            (s) => [s.rowsStats, s.billing],
            (
                rowsStats: PipelineRowsStatsResponseApi | null,
                billing: BillingType | null
            ): Record<string, SourceUsage> | null => {
                if (!rowsStats?.billing_available) {
                    return null
                }
                const billableRows = rowsStats.billable_rows_by_source
                const costs = estimateSourceCostsUsd(
                    billableRows,
                    billing?.products?.find((product) => product.type === SYNCED_ROWS_BILLING_PRODUCT)
                )
                return Object.fromEntries(
                    Object.entries(billableRows).map(([sourceId, rows]) => [
                        sourceId,
                        { billableRows: rows, costUsd: costs?.[sourceId] ?? null },
                    ])
                )
            },
        ],
        showSourceCost: [
            (s) => [s.sourceUsageById],
            (sourceUsageById: Record<string, SourceUsage> | null): boolean =>
                !!sourceUsageById && Object.values(sourceUsageById).some((usage) => usage.costUsd !== null),
        ],
    }),
    afterMount(({ actions, values }) => {
        actions.loadRowsStats()
        // billingLogic doesn't load on mount, and the cost column needs it on a cold page load.
        if (!values.billing) {
            actions.loadBilling()
        }
    }),
])
