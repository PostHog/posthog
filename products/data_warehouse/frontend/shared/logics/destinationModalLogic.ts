export type destinationModalLogicType = MakeLogicType<
    destinationModalLogicValues,
    destinationModalLogicActions,
    DestinationModalLogicProps,
    destinationModalLogicMeta
>

export const destinationModalLogic = kea<destinationModalLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'shared', 'logics', 'destinationModalLogic']),
    props({} as DestinationModalLogicProps),
    key((props: DestinationModalLogicProps) => props.modalKey),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], integrationsLogic, ['integrations']],
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        openForCreate: true,
        openForEdit: (destination: ExternalDataDestinationApi) => ({ destination }),
        closeModal: true,
        deleteDestination: (destination: ExternalDataDestinationApi) => ({ destination }),
        setDestinationType: (type: CreatableDestinationType) => ({ type }),
        setIntegrationKind: (kind: IntegrationKind) => ({ kind }),
    }),
    reducers({
        isOpen: [
            false,
            {
                openForCreate: () => true,
                openForEdit: () => true,
                closeModal: () => false,
            },
        ],
        editing: [
            null as ExternalDataDestinationApi | null,
            {
                openForCreate: () => null,
                openForEdit: (_, { destination }) => destination,
                closeModal: () => null,
            },
        ],
    }),
    forms(({ values, props, actions }: any) => ({
        destinationForm: {
            defaults: newDestinationForm(),
            errors: (formValues: DestinationFormValues) => ({
                name: !formValues.name?.trim() ? 'Give this destination a name' : undefined,
                integrationId: formValues.integrationId ? undefined : 'Pick a connection',
                ...validateDestinationFields(
                    WAREHOUSE_DESTINATIONS[formValues.type] ?? WAREHOUSE_DESTINATIONS[DEFAULT_TYPE],
                    {
                        isNew: !values.editing,
                        formValues,
                    }
                ),
            }),
            submit: async (formValues: DestinationFormValues) => {
                const definition = WAREHOUSE_DESTINATIONS[formValues.type] ?? WAREHOUSE_DESTINATIONS[DEFAULT_TYPE]
                const payload = {
                    type: formValues.type,
                    name: formValues.name.trim(),
                    integration: formValues.integrationId,
                    config: buildDestinationConfig(definition, formValues),
                }
                const teamId = String(values.currentTeamId)
                const saved = values.editing
                    ? await externalDataDestinationsPartialUpdate(teamId, values.editing.id, payload)
                    : await externalDataDestinationsCreate(teamId, payload)

                lemonToast.success(values.editing ? 'Destination updated' : 'Destination added')
                actions.closeModal()
                props.onSaved(saved)
            },
        },
    })),
    // Declared after `forms`, because `definition` and `availableIntegrations` read
    // `destinationForm`, and the forms plugin only adds that value when it is applied.
    selectors({
        definition: [
            (s: any) => [s.destinationForm],
            (destinationForm: DestinationFormValues): WarehouseDestinationDefinition =>
                WAREHOUSE_DESTINATIONS[destinationForm.type] ?? WAREHOUSE_DESTINATIONS[DEFAULT_TYPE],
        ],
        availableIntegrations: [
            (s: any) => [s.integrations, s.destinationForm],
            (integrations: IntegrationType[] | null, destinationForm: DestinationFormValues): IntegrationType[] =>
                (integrations ?? []).filter((integration) => integration.kind === destinationForm.integrationKind),
        ],
        // Null while integrations load, or if the integration was deleted.
        editingIntegration: [
            (s: any) => [s.editing, s.integrations],
            (
                editing: ExternalDataDestinationApi | null,
                integrations: IntegrationType[] | null
            ): IntegrationType | null =>
                (editing?.integration && integrations?.find((one) => one.id === editing.integration)) || null,
        ],
    }),
    listeners(({ actions, values, props }: any) => ({
        deleteDestination: ({ destination }: { destination: ExternalDataDestinationApi }) => {
            LemonDialog.open({
                title: `Delete ${destination.name}?`,
                description:
                    'Every source and table that syncs here stops doing so. Tables already written ' +
                    'to it are left where they are, and runs already under way finish first. ' +
                    'This cannot be undone.',
                primaryButton: {
                    children: 'Delete destination',
                    status: 'danger',
                    onClick: async () => {
                        try {
                            await externalDataDestinationsDestroy(String(values.currentTeamId), destination.id)
                            lemonToast.success(`Deleted ${destination.name}`)
                            actions.closeModal()
                            props.onDeleted?.(destination.id)
                        } catch (e: any) {
                            lemonToast.error(e.detail ?? `Could not delete ${destination.name}`)
                        }
                    },
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        openForCreate: () => {
            actions.loadIntegrations()
            actions.resetDestinationForm(newDestinationForm())
            actions.setDestinationType(DEFAULT_TYPE)
        },
        openForEdit: ({ destination }: { destination: ExternalDataDestinationApi }) => {
            actions.loadIntegrations()
            const type = destination.type as CreatableDestinationType
            const definition = WAREHOUSE_DESTINATIONS[type]
            if (!definition) {
                lemonToast.error(`${destination.name} has an unsupported type and cannot be edited here`)
                actions.closeModal()
                return
            }
            const config = (destination.config ?? {}) as Record<string, any>
            actions.resetDestinationForm({
                name: destination.name,
                type,
                integrationId: destination.integration ?? null,
                integrationKind: definition.integrationKinds[0],
                ...buildDestinationFormValues(definition, config),
            })
        },
        // Carrying the old type's fields over would leave values in the form that
        // `buildDestinationConfig` then drops silently at save time.
        setDestinationType: ({ type }: { type: CreatableDestinationType }) => {
            const name = values.destinationForm.name
            actions.resetDestinationForm({ ...newDestinationForm(type), name })
            actions.setIntegrationKind(WAREHOUSE_DESTINATIONS[type].integrationKinds[0])
        },
        setIntegrationKind: ({ kind }: { kind: IntegrationKind }) => {
            const matching = (values.integrations ?? []).filter((one: IntegrationType) => one.kind === kind)
            actions.setDestinationFormValues({
                integrationKind: kind,
                integrationId: matching.length === 1 ? matching[0].id : null,
            })
        },
        // Integrations arrive after the modal opens, so the preselect has to run again once they
        // do. Keyed off `integrationsLogic`'s own action: a bare `loadIntegrationsSuccess` key
        // would register a listener for an action this logic does not have, and never fire.
        [integrationsLogic.actionTypes.loadIntegrationsSuccess]: () => {
            if (values.editing || values.destinationForm.integrationId) {
                return
            }
            actions.setIntegrationKind(values.destinationForm.integrationKind)
        },
    })),
])
