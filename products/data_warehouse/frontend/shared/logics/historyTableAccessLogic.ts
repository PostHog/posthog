import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import { FEATURE_FLAGS } from 'lib/constants'
import { LemonDialog } from 'lib/lemon-ui/LemonDialog'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { featureFlagLogic, FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { captureAccessControlEvent } from 'lib/utils/accessControlUtils'
import { teamLogic } from 'scenes/teamLogic'

import { accessControlLogic } from '~/layout/navigation-3000/sidepanel/panels/access_control/accessControlLogic'
import {
    AccessControlLevel,
    AccessControlResourceType,
    AccessControlType,
    AccessControlUpdateType,
    OrganizationMemberType,
    RoleType,
} from '~/types'

import { warehouseTablesHistoryTableRetrieve } from 'products/data_warehouse/frontend/generated/api'
import type { HistoryTableRefApi } from 'products/data_warehouse/frontend/generated/api.schemas'

export interface HistoryTableAccessLogicProps {
    tableId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface historyTableAccessLogicValues {
    currentProjectId: number | null // teamLogic
    featureFlags: FeatureFlagsSet // featureFlagLogic
    historyTable: HistoryTableRefApi | null
    historyTableLoading: boolean
}

export interface historyTableAccessLogicActions {
    updateAccessControlDefaultSuccess: (
        accessControls: any,
        payload?: { level: AccessControlLevel | null; source: any }
    ) => {
        accessControls: any
        payload?: { level: AccessControlLevel | null; source: any }
    } // accessControlLogic
    updateAccessControlMembersSuccess: (
        accessControls: any,
        payload?: { accessControls: { member: OrganizationMemberType['id']; level: AccessControlLevel | null }[] }
    ) => {
        accessControls: any
        payload?: { accessControls: { member: OrganizationMemberType['id']; level: AccessControlLevel | null }[] }
    } // accessControlLogic
    updateAccessControlRolesSuccess: (
        accessControls: any,
        payload?: { accessControls: { role: RoleType['id']; level: AccessControlLevel | null }[] }
    ) => {
        accessControls: any
        payload?: { accessControls: { role: RoleType['id']; level: AccessControlLevel | null }[] }
    } // accessControlLogic
    offerToApplyToHistoryTable: (rules: AccessControlUpdateType[]) => { rules: AccessControlUpdateType[] }
    applyToHistoryTable: (rules: AccessControlUpdateType[]) => { rules: AccessControlUpdateType[] }
    loadHistoryTable: () => void
    loadHistoryTableSuccess: (
        historyTable: HistoryTableRefApi | null,
        payload?: any
    ) => { historyTable: HistoryTableRefApi | null; payload?: any }
    loadHistoryTableFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
}

export type historyTableAccessLogicType = MakeLogicType<
    historyTableAccessLogicValues,
    historyTableAccessLogicActions,
    HistoryTableAccessLogicProps
>

/** Offers to repeat each access rule change of a table on its history table, which has rules of its own. */
export const historyTableAccessLogic = kea<historyTableAccessLogicType>([
    props({} as HistoryTableAccessLogicProps),
    key((props) => props.tableId),
    path((key) => ['products', 'data_warehouse', 'shared', 'logics', 'historyTableAccessLogic', key]),
    connect((props: HistoryTableAccessLogicProps) => ({
        values: [teamLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']],
        actions: [
            // The key is the resource and id. The dialog renders its own title and description.
            accessControlLogic({
                resource: AccessControlResourceType.WarehouseTable,
                resource_id: props.tableId,
                title: '',
                description: '',
            }),
            [
                'updateAccessControlDefaultSuccess',
                'updateAccessControlMembersSuccess',
                'updateAccessControlRolesSuccess',
            ],
        ],
    })),
    actions({
        offerToApplyToHistoryTable: (rules: AccessControlUpdateType[]) => ({ rules }),
        applyToHistoryTable: (rules: AccessControlUpdateType[]) => ({ rules }),
    }),
    loaders(({ props, values }) => ({
        historyTable: [
            null as HistoryTableRefApi | null,
            {
                loadHistoryTable: async () => {
                    try {
                        const response = await warehouseTablesHistoryTableRetrieve(
                            String(values.currentProjectId),
                            props.tableId
                        )
                        return response.history_table ?? null
                    } catch {
                        // The offer is optional, so a failed lookup only means no offer.
                        return null
                    }
                },
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        updateAccessControlDefaultSuccess: ({ payload }) => {
            if (payload) {
                actions.offerToApplyToHistoryTable([{ access_level: payload.level }])
            }
        },
        updateAccessControlMembersSuccess: ({ payload }) => {
            if (payload) {
                actions.offerToApplyToHistoryTable(
                    payload.accessControls.map(({ member, level }) => ({
                        organization_member: member,
                        access_level: level,
                    }))
                )
            }
        },
        updateAccessControlRolesSuccess: ({ payload }) => {
            if (payload) {
                actions.offerToApplyToHistoryTable(
                    payload.accessControls.map(({ role, level }) => ({ role, access_level: level }))
                )
            }
        },
        offerToApplyToHistoryTable: ({ rules }) => {
            const historyTable = values.historyTable
            if (!historyTable || rules.length === 0) {
                return
            }
            captureAccessControlEvent('history table access rules offered', { trigger: 'rule_change' })
            const answer = (accepted: boolean): void =>
                captureAccessControlEvent('history table access rules answered', { trigger: 'rule_change', accepted })
            LemonDialog.open({
                title: 'Apply this change to the history table?',
                description: `${historyTable.name} keeps every past version of this table's rows. It has its own access rules, so this change doesn't apply to it unless you apply it there too.`,
                primaryButton: {
                    children: 'Apply to history table',
                    onClick: () => {
                        answer(true)
                        actions.applyToHistoryTable(rules)
                    },
                    'data-attr': 'history-access-rules-apply',
                },
                secondaryButton: {
                    children: 'Not now',
                    onClick: () => answer(false),
                    'data-attr': 'history-access-rules-not-now',
                },
            })
        },
        applyToHistoryTable: async ({ rules }) => {
            const historyTable = values.historyTable
            if (!historyTable) {
                return
            }
            const endpoint = `api/projects/${values.currentProjectId}/warehouse_tables/${historyTable.id}/access_controls`
            try {
                for (const rule of rules) {
                    // nosemgrep: prefer-codegen-api -- the access_controls action is excluded from the OpenAPI schema, so no generated function covers it.
                    await api.put<AccessControlType, AccessControlUpdateType>(endpoint, rule)
                }
                lemonToast.success(`Applied the change to ${historyTable.name}`)
            } catch {
                lemonToast.error(
                    `Couldn't apply the change to ${historyTable.name}. Open its access settings to change it there.`
                )
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.featureFlags[FEATURE_FLAGS.WAREHOUSE_HISTORY_ACCESS_RULES]) {
            actions.loadHistoryTable()
        }
    }),
])
