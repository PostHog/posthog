/** Offers to copy a table's access rules to its history table, which has rules of its own. */
export const historyTableAccessLogic = kea<historyTableAccessLogicType>([
    props({} as HistoryTableAccessLogicProps),
    key((props) => props.tableId),
    path((key) => ['products', 'data_warehouse', 'shared', 'logics', 'historyTableAccessLogic', key]),
    connect((props: HistoryTableAccessLogicProps) => ({
        values: [
            teamLogic,
            ['currentProjectId'],
            featureFlagLogic,
            ['featureFlags'],
            // The key is the resource and id. The dialog renders its own title and description.
            accessControlLogic({
                resource: AccessControlResourceType.WarehouseTable,
                resource_id: props.tableId,
                title: '',
                description: '',
            }),
            ['accessControls', 'accessControlsLoading'],
        ],
    })),
    actions({
        confirmCopyToHistoryTable: true,
        copyToHistoryTable: true,
        setCopying: (copying: boolean) => ({ copying }),
    }),
    reducers({
        copying: [false, { setCopying: (_, { copying }) => copying }],
    }),
    loaders(({ props, values }) => ({
        historyTable: [
            null as HistoryTableRefApi | null,
            {
                loadHistoryTable: async () => {
                    try {
                        const response = await warehouseTablesHistoryTableRetrieve(
                            String(values.currentProjectId),
                            props.tableId
                        )
                        return response.history_table ?? null
                    } catch {
                        // The offer is optional, so a failed lookup only means no offer.
                        return null
                    }
                },
            },
        ],
    })),
    selectors({
        canCopyToHistoryTable: [
            (s) => [s.featureFlags, s.historyTable, s.accessControls],
            (
                featureFlags: FeatureFlagsSet,
                historyTable: HistoryTableRefApi | null,
                accessControls: AccessControlResponseType | null
            ): boolean =>
                !!featureFlags[FEATURE_FLAGS.WAREHOUSE_HISTORY_ACCESS_RULES] &&
                !!historyTable?.user_can_manage_access &&
                !!accessControls?.user_can_edit_access_levels,
        ],
        // A copy started while a rule change saves would read the rules from before the change.
        copyDisabledReason: [
            (s) => [s.accessControlsLoading],
            (accessControlsLoading: boolean): string | null =>
                accessControlsLoading ? 'Wait for the access change to save.' : null,
        ],
    }),
    listeners(({ actions, props, values }) => ({
        confirmCopyToHistoryTable: () => {
            const historyTable = values.historyTable
            if (!historyTable) {
                return
            }
            captureAccessControlEvent('history table access rules offered', { trigger: 'access_dialog' })
            const answer = (accepted: boolean): void =>
                captureAccessControlEvent('history table access rules answered', { trigger: 'access_dialog', accepted })
            LemonDialog.open({
                title: 'Copy access rules to the history table?',
                description: `${historyTable.name} gets this table's access rules. This replaces the history table's current rules.`,
                primaryButton: {
                    children: 'Copy rules',
                    onClick: () => {
                        answer(true)
                        actions.copyToHistoryTable()
                    },
                    'data-attr': 'history-access-rules-copy-from-dialog',
                },
                secondaryButton: {
                    children: 'Cancel',
                    onClick: () => answer(false),
                    'data-attr': 'history-access-rules-cancel-from-dialog',
                },
            })
        },
        copyToHistoryTable: async () => {
            const historyTable = values.historyTable
            if (!historyTable) {
                return
            }
            actions.setCopying(true)
            try {
                await warehouseTablesCopyAccessRulesToHistoryTableCreate(String(values.currentProjectId), props.tableId)
                lemonToast.success(`Copied the access rules to ${historyTable.name}`)
            } catch {
                lemonToast.error(
                    `Couldn't copy the access rules to ${historyTable.name}. Open its access settings to change them there.`
                )
            } finally {
                actions.setCopying(false)
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.featureFlags[FEATURE_FLAGS.WAREHOUSE_HISTORY_ACCESS_RULES]) {
            actions.loadHistoryTable()
        }
    }),
])
