import { userLogic } from 'scenes/userLogic'

import { UI_CONFIGURATION_VERSION } from '~/layout/uiCustomizationLogic'
import { SQLEditorConfiguration, UserUIConfiguration } from '~/queries/schema/schema-general'
import { UserType } from '~/types'

// The server replaces ui_configuration wholesale, so every other key, such as the sidebar settings, must be carried over.
export function withSqlEditorPatch(
    configuration: UserUIConfiguration | null,
    patch: Partial<SQLEditorConfiguration>
): UserUIConfiguration {
    return {
        version: UI_CONFIGURATION_VERSION,
        ...configuration,
        sql_editor: { ...configuration?.sql_editor, ...patch },
    }
}

