export const sqlEditorVimLogic = kea<sqlEditorVimLogicType>([
    path(['products', 'data_warehouse', 'frontend', 'shared', 'logics', 'sqlEditorVimLogic']),
    connect(() => ({
        values: [userLogic, ['user'], userPreferencesLogic, ['editorVimModeEnabled']],
        actions: [userLogic, ['updateUser', 'updateUserSuccess', 'updateUserFailure']],
    })),
    actions({
        setVimModeEnabled: (enabled: boolean) => ({ enabled }),
        setEditorSettingsMenuOpen: (editorKey: string, open: boolean) => ({ editorKey, open }),
        openVimrcModal: (editorKey: string) => ({ editorKey }),
        closeVimrcModal: true,
        setVimrcDraft: (vimrcDraft: string) => ({ vimrcDraft }),
        saveVimrc: true,
        setPendingSqlEditorConfiguration: (configuration: SQLEditorConfiguration | null) => ({ configuration }),
    }),
    reducers({
        pendingSqlEditorConfiguration: [
            null as SQLEditorConfiguration | null,
            {
                setPendingSqlEditorConfiguration: (_, { configuration }) => configuration,
                // Other account updates also dispatch this, so clear only when the request that carried this object finishes.
                updateUserSuccess: (state, { payload }) =>
                    payload?.user.ui_configuration?.sql_editor === state ? null : state,
                updateUserFailure: () => null,
            },
        ],
        // The vimrc modal opens from the editor settings menu, which would otherwise stay open on top of the modal.
        editorSettingsMenuKey: [
            null as string | null,
            {
                setEditorSettingsMenuOpen: (state, { editorKey, open }) =>
                    open ? editorKey : state === editorKey ? null : state,
                openVimrcModal: () => null,
            },
        ],
        vimrcEditorKey: [
            null as string | null,
            {
                openVimrcModal: (_, { editorKey }) => editorKey,
                closeVimrcModal: () => null,
            },
        ],
        vimrcDraft: [
            '',
            {
                setVimrcDraft: (_, { vimrcDraft }) => vimrcDraft,
            },
        ],
        vimrcSaving: [
            false,
            {
                saveVimrc: () => true,
                closeVimrcModal: () => false,
                updateUserFailure: () => false,
            },
        ],
    }),
    selectors({
        isVimrcModalOpen: [
            (s) => [s.vimrcEditorKey],
            (vimrcEditorKey: string | null): boolean => vimrcEditorKey !== null,
        ],
        // Writes build on this, so a second change made while the first PATCH is in flight keeps the first change.
        uiConfiguration: [
            (s) => [s.user, s.pendingSqlEditorConfiguration],
            (
                user: UserType | null,
                pendingSqlEditorConfiguration: SQLEditorConfiguration | null
            ): UserUIConfiguration | null => {
                const saved = user?.ui_configuration ?? null
                return pendingSqlEditorConfiguration ? withSqlEditorPatch(saved, pendingSqlEditorConfiguration) : saved
            },
        ],
        sqlEditorConfiguration: [
            (s) => [s.uiConfiguration],
            (uiConfiguration: UserUIConfiguration | null): SQLEditorConfiguration | null =>
                uiConfiguration?.sql_editor ?? null,
        ],
        vimModeEnabled: [
            (s) => [s.sqlEditorConfiguration, s.editorVimModeEnabled],
            // Users who turned Vim mode on before it was saved to their account keep it until they change it.
            (sqlEditorConfiguration: SQLEditorConfiguration | null, editorVimModeEnabled: boolean): boolean =>
                sqlEditorConfiguration?.vim_mode_enabled ?? editorVimModeEnabled,
        ],
        vimrc: [
            (s) => [s.sqlEditorConfiguration],
            (sqlEditorConfiguration: SQLEditorConfiguration | null): string => sqlEditorConfiguration?.vimrc ?? '',
        ],
        vimrcDraftErrors: [(s) => [s.vimrcDraft], (vimrcDraft: string): VimrcError[] => parseVimrc(vimrcDraft).errors],
        vimrcTooLong: [(s) => [s.vimrcDraft], (vimrcDraft: string): boolean => vimrcDraft.length > VIMRC_MAX_LENGTH],
    }),
    listeners(({ actions, values }) => ({
        setVimModeEnabled: ({ enabled }) => {
            const configuration = withSqlEditorPatch(values.uiConfiguration, { vim_mode_enabled: enabled })
            actions.setPendingSqlEditorConfiguration(configuration.sql_editor ?? null)
            actions.updateUser({ ui_configuration: configuration })
            posthog.capture('sql editor vim mode toggled', { enabled })
        },
        openVimrcModal: () => {
            actions.setVimrcDraft(values.vimrc)
            posthog.capture('sql editor vimrc opened', { has_vimrc: values.vimrc.trim().length > 0 })
        },
        saveVimrc: () => {
            const vimrc = values.vimrcDraft
            const configuration = withSqlEditorPatch(values.uiConfiguration, { vimrc })
            actions.setPendingSqlEditorConfiguration(configuration.sql_editor ?? null)
            actions.updateUser({ ui_configuration: configuration }, () => {
                actions.closeVimrcModal()
                // Counts only. The vimrc text is free text the user typed, so it never leaves the browser in an event.
                posthog.capture('sql editor vimrc saved', {
                    line_count: vimrc.split('\n').length,
                    command_count: parseVimrc(vimrc).commands.length,
                })
            })
        },
    })),
])
