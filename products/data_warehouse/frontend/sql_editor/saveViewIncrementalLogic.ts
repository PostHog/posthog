export const saveViewIncrementalLogic: LogicWrapper<saveViewIncrementalLogicType> = kea<saveViewIncrementalLogicType>([
    props({} as SaveViewIncrementalLogicProps),
    key(({ dialogKey, query }) => `${dialogKey}:${query}`),
    path((key) => ['products', 'data_warehouse', 'sql_editor', 'saveViewIncrementalLogic', key]),
    connect((props: SaveViewIncrementalLogicProps) => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [lemonDialogLogic({ dialogKey: props.dialogKey }), ['setFormValue']],
    })),
    loaders(({ actions, props, values }) => ({
        check: [
            null as IncrementalEligibilityApi | null,
            {
                loadCheck: async (_: void, breakpoint) => {
                    // Form actions update the parent dialog, so wait for the mounting render to finish.
                    await breakpoint(0)
                    actions.setFormValue('incrementalEnabled', false)
                    actions.setFormValue('incrementalKey', null)
                    actions.setFormValue('incrementalUniqueKey', [])
                    const teamId = values.currentTeamId
                    if (teamId === null) {
                        return null
                    }
                    let check: IncrementalEligibilityApi | null = null
                    try {
                        check = await api.warehouseSavedQueriesCheckIncrementalCreate(String(teamId), {
                            query: props.query,
                        })
                    } catch (error) {
                        if (!(error instanceof ApiError && error.status && error.status >= 400 && error.status < 500)) {
                            posthog.captureException(error)
                        }
                    }
                    breakpoint()
                    return check
                },
            },
        ],
    })),
    listeners(({ actions }) => ({
        loadCheckSuccess: ({ check }) => {
            actions.setFormValue('incrementalKey', check?.key_candidates[0] ?? null)
        },
    })),
    afterMount(({ actions, props }) => {
        if (props.enabled) {
            actions.loadCheck()
        }
    }),
    propsChanged(({ actions, props, values }, oldProps) => {
        if (props.enabled && !oldProps.enabled && !values.check && !values.checkLoading) {
            actions.loadCheck()
        }
    }),
])
