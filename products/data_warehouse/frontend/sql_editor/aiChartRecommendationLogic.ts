export const aiChartRecommendationLogic: LogicWrapper<aiChartRecommendationLogicType> =
    kea<aiChartRecommendationLogicType>([
        path(['products', 'data_warehouse', 'sql_editor', 'aiChartRecommendationLogic']),
        props({} as AIChartRecommendationProps),
        key((props) => props.visualizationProps.key),
        connect((props: AIChartRecommendationProps) => ({
            values: [
                dataVisualizationLogic(props.visualizationProps),
                ['query', 'columns', 'response', 'responseLoading'],
                outputPaneLogic({ tabId: props.tabId }),
                ['activeTab'],
                aiConsentLogic,
                ['dataProcessingAccepted'],
                featureFlagLogic,
                ['featureFlags'],
                preflightLogic,
                ['preflight'],
                teamLogic,
                ['currentTeamId'],
            ],
            actions: [
                dataVisualizationLogic(props.visualizationProps),
                ['setQuery', '_setQuery'],
                outputPaneLogic({ tabId: props.tabId }),
                ['setActiveTab'],
                dataNodeLogic({ key: props.visualizationProps.key, query: props.visualizationProps.query.source }),
                ['loadData', 'loadDataSuccess', 'loadDataFailure'],
            ],
        })),
        actions({
            skipRecommendation: true,
            setRecommendationStatus: (status: RecommendationStatus) => ({ status }),
        }),
        reducers({
            recommendationStatus: [
                'idle' as RecommendationStatus,
                {
                    setRecommendationStatus: (_, { status }) => status,
                    skipRecommendation: (): RecommendationStatus => 'skipped',
                },
            ],
            recommendationPending: [
                false,
                {
                    recommendChart: () => true,
                    recommendChartSuccess: () => false,
                    recommendChartFailure: () => false,
                    skipRecommendation: () => false,
                    loadData: () => false,
                },
            ],
        }),
        selectors({
            statusMessage: [
                (s) => [s.featureFlags, s.dataProcessingAccepted, s.enabled, s.recommendationStatus],
                (
                    flags: FeatureFlagsSet,
                    consent: boolean,
                    enabled: boolean,
                    status: RecommendationStatus
                ): string | null => {
                    if (!flags[FEATURE_FLAGS.JEV_CHART_AUTODETECTION]) {
                        return null
                    }
                    if (!consent) {
                        return 'AI chart selection needs organization AI consent'
                    }
                    if (!enabled) {
                        return 'AI chart selection is unavailable'
                    }
                    return {
                        idle: 'AI chart selection is ready',
                        loading: 'Choosing a chart…',
                        selected: 'Chart and layout selected by AI',
                        reused: 'Keeping the chart for unchanged columns',
                        fallback: 'AI chart selection could not finish. Using default visualization.',
                        skipped: 'AI chart selection skipped',
                    }[status]
                },
            ],
            enabled: [
                (s) => [s.dataProcessingAccepted, s.featureFlags, s.preflight],
                (consent: boolean, flags: FeatureFlagsSet, preflight: PreflightStatus | null): boolean =>
                    consent &&
                    !!flags[FEATURE_FLAGS.JEV_CHART_AUTODETECTION] &&
                    !!(preflight?.is_debug || flags[FEATURE_FLAGS.ML_INFERENCE_DECISIONS]),
            ],
            choosingChart: [
                (s) => [s.recommendationPending, s.enabled, s.responseLoading],
                (pending: boolean, enabled: boolean, responseLoading: boolean): boolean =>
                    pending && enabled && !responseLoading,
            ],
        }),
        loaders(({ values, actions, cache }) => ({
            recommendation: [
                null as ChartRecommendation | null,
                {
                    recommendChart: async (_: void, breakpoint) => {
                        cache.disposables.dispose('chartDecision')
                        // Let the existing column subscription finish setting its fallback axes first.
                        await breakpoint(0)
                        if (
                            !values.recommendationPending ||
                            !values.enabled ||
                            values.currentTeamId === null ||
                            values.responseLoading
                        ) {
                            return null
                        }
                        const query = values.query
                        const presentation = presentationKey(query, values.activeTab)
                        if (query.display !== ChartDisplayType.Auto && presentation !== cache.lastAppliedPresentation) {
                            return null
                        }
                        const response = values.response
                        const rows: unknown[][] =
                            response && 'results' in response && Array.isArray(response.results) ? response.results : []
                        const columns = values.columns
                        const request = buildChartDecision(columns, rows)
                        if (!request) {
                            actions.setRecommendationStatus('fallback')
                            return null
                        }
                        const teamId = values.currentTeamId
                        const cached: CachedDecision | undefined = cache.cachedDecision
                        const reused =
                            cached?.teamId === teamId &&
                            cached.columnsKey === columnKey(columns) &&
                            cached.singleRow === (rows.length === 1) &&
                            !!readChartDecision(cached.decision, columns, rows)
                        actions.setRecommendationStatus(reused ? 'reused' : 'loading')
                        const preview: ChartPreview | undefined = cache.chartPreview
                        const controller = new AbortController()
                        cache.disposables.add(() => () => controller.abort(), 'chartDecision', {
                            pauseOnPageHidden: false,
                        })
                        try {
                            const resolveDecision = async (): Promise<DecideResponseApi | null> => {
                                if (reused && cached) {
                                    return cached.decision
                                }
                                const prediction =
                                    preview?.teamId === teamId && preview.sourceKey === chartSourceKey(query.source)
                                        ? await preview.promise
                                        : null
                                if (
                                    controller.signal.aborted ||
                                    !values.enabled ||
                                    !values.recommendationPending ||
                                    values.currentTeamId !== teamId ||
                                    values.response !== response ||
                                    JSON.stringify(values.query.source) !== JSON.stringify(query.source)
                                ) {
                                    return null
                                }
                                if (
                                    prediction?.decision &&
                                    columnKey(prediction.columns) === columnKey(columns) &&
                                    readChartDecision(prediction.decision, columns, rows)
                                ) {
                                    return prediction.decision
                                }
                                return decisionsApi.mlInferenceDecisionsDecideCreate(String(teamId), request, {
                                    signal: controller.signal,
                                })
                            }
                            const result = await withTimeout(resolveDecision(), 5000)
                            breakpoint()
                            if (
                                controller.signal.aborted ||
                                !result ||
                                !values.recommendationPending ||
                                !values.enabled ||
                                values.currentTeamId !== teamId ||
                                values.response !== response ||
                                values.responseLoading ||
                                JSON.stringify(values.query.source) !== JSON.stringify(query.source) ||
                                presentationKey(values.query, values.activeTab) !== presentation
                            ) {
                                return null
                            }
                            const recommendation = readChartDecision(result, columns, rows)
                            if (!recommendation) {
                                actions.setRecommendationStatus('fallback')
                                return null
                            }
                            const node: VisualizationNode = {
                                ...values.query,
                                display: recommendation.display,
                                chartSettings: recommendation.chartSettings,
                            }
                            cache.fallbackPresentation ??= {
                                display: query.display,
                                chartSettings: query.chartSettings,
                                tab: values.activeTab,
                            }
                            actions._setQuery(node)
                            actions.setQuery(() => node)
                            actions.setActiveTab(recommendation.outputTab)
                            cache.lastAppliedPresentation = presentationKey(node, recommendation.outputTab)
                            cache.cachedDecision = {
                                columnsKey: columnKey(columns),
                                singleRow: rows.length === 1,
                                teamId,
                                decision: result,
                            } satisfies CachedDecision
                            actions.setRecommendationStatus(reused ? 'reused' : 'selected')
                            return recommendation
                        } catch {
                            breakpoint()
                            if (!controller.signal.aborted) {
                                actions.setRecommendationStatus('fallback')
                            }
                            return null
                        } finally {
                            if (!controller.signal.aborted && values.recommendationStatus === 'loading') {
                                actions.setRecommendationStatus('fallback')
                            }
                            controller.abort()
                            preview?.controller.abort()
                        }
                    },
                },
            ],
        })),
        listeners(({ actions, values, cache }) => ({
            loadDataFailure: () => {
                actions.skipRecommendation()
            },
            skipRecommendation: () => {
                cache.disposables.dispose('chartDecision')
                cache.disposables.dispose('chartPreview')
            },
            loadData: ({ overrideQuery, pollOnly }) => {
                cache.disposables.dispose('chartDecision')
                cache.disposables.dispose('chartPreview')
                cache.chartPreview = undefined
                if (
                    cache.lastAppliedPresentation === presentationKey(values.query, values.activeTab) &&
                    cache.fallbackPresentation
                ) {
                    const { display, chartSettings, tab } = cache.fallbackPresentation
                    const node = { ...values.query, display, chartSettings }
                    actions._setQuery(node)
                    actions.setQuery(() => node)
                    if (!values.enabled) {
                        actions.setActiveTab(tab)
                    }
                } else {
                    cache.fallbackPresentation = undefined
                }
                cache.lastAppliedPresentation = undefined
                const source = overrideQuery ?? values.query.source
                const teamId = values.currentTeamId
                if (
                    !pollOnly &&
                    values.enabled &&
                    teamId !== null &&
                    values.query.display === ChartDisplayType.Auto &&
                    isHogQLQuery(source) &&
                    !source.sendRawQuery
                ) {
                    actions.setRecommendationStatus('loading')
                    const sourceKey = chartSourceKey(source)
                    const controller = new AbortController()
                    const isCurrent = (): boolean =>
                        !controller.signal.aborted &&
                        values.enabled &&
                        values.currentTeamId === teamId &&
                        values.query.display === ChartDisplayType.Auto &&
                        chartSourceKey(values.query.source) === sourceKey
                    cache.disposables.add(() => () => controller.abort(), 'chartPreview', {
                        pauseOnPageHidden: false,
                    })
                    cache.chartPreview = {
                        sourceKey,
                        teamId,
                        controller,
                        promise: withTimeout(
                            previewChart(source, teamId, controller.signal, isCurrent, cache.cachedDecision),
                            5000
                        )
                            .catch(() => ({ columns: [], decision: null }))
                            .finally(() => controller.abort()),
                    } satisfies ChartPreview
                } else {
                    actions.setRecommendationStatus('idle')
                }
            },
            loadDataSuccess: () => {
                const response = values.response
                if (
                    values.enabled &&
                    values.currentTeamId !== null &&
                    (values.query.display === ChartDisplayType.Auto ||
                        presentationKey(values.query, values.activeTab) === cache.lastAppliedPresentation) &&
                    response &&
                    'results' in response &&
                    Array.isArray(response.results) &&
                    response.results.length > 0
                ) {
                    actions.recommendChart()
                }
            },
        })),
    ])
