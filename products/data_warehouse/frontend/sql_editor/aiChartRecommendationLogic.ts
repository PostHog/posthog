export interface AIChartRecommendationProps {
    visualizationProps: DataVisualizationLogicProps
    tabId: string
}

function presentationKey(query: VisualizationNode, tab: OutputTab): string {
    return JSON.stringify([query.display, query.chartSettings, tab])
}

function chartSourceKey(source: VisualizationNode['source']): string {
    return JSON.stringify({ ...source, tags: undefined })
}

interface ChartPreviewResult {
    columns: Column[]
    decision: DecideResponseApi | null
}

interface ChartPreview {
    sourceKey: string
    teamId: number
    controller: AbortController
    promise: Promise<ChartPreviewResult | null>
}

function columnKey(columns: Column[]): string {
    return JSON.stringify(columns.map(({ name, type }) => [name, type.name]))
}

type RecommendationStatus = 'idle' | 'loading' | 'selected' | 'reused' | 'fallback' | 'skipped'

interface CachedDecision {
    columnsKey: string
    singleRow: boolean
    teamId: number
    decision: DecideResponseApi
}

async function previewChart(
    source: HogQLQuery,
    teamId: number,
    signal: AbortSignal,
    isCurrent: () => boolean,
    cachedDecision?: CachedDecision
): Promise<ChartPreviewResult | null> {
    const metadata = await performQuery<HogQLMetadata>(
        {
            kind: NodeKind.HogQLMetadata,
            language: HogLanguage.hogQL,
            query: source.query,
            connectionId: source.connectionId,
            filters: source.filters,
            variables: source.variables,
            globals: source.values,
            modifiers: source.modifiers,
            includeOutputTypes: true,
        },
        { signal }
    )
    if (
        !isCurrent() ||
        !metadata.isValid ||
        !metadata.output_columns?.length ||
        metadata.output_columns.some((column) => /Unknown|Any/.test(column.type))
    ) {
        return null
    }
    const columns = columnsFromResponse({
        columns: metadata.output_columns.map((column) => column.name),
        types: metadata.output_columns.map((column) => [column.name, column.type]),
    })
    if (cachedDecision?.teamId === teamId && cachedDecision.columnsKey === columnKey(columns)) {
        return { columns, decision: null }
    }
    const request = buildChartDecision(columns, undefined, source.query)
    if (!request) {
        return null
    }
    try {
        return {
            columns,
            decision: await decisionsApi.mlInferenceDecisionsDecideCreate(String(teamId), request, { signal }),
        }
    } catch {
        return { columns, decision: null }
    }
}

