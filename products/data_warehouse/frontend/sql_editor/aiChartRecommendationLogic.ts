export const aiChartRecommendationLogic: LogicWrapper<aiChartRecommendationLogicType> =
    kea<aiChartRecommendationLogicType>([
        path(['products', 'data_warehouse', 'sql_editor', 'aiChartRecommendationLogic']),
        props({} as AIChartRecommendationProps),
        key((props) => props.visualizationProps.key),
        connect((props: AIChartRecommendationProps) => ({
            values: [
                dataVisualizationLogic(props.visualizationProps),
                ['query', 'columns', 'response', 'responseLoading'],
                outputPaneLogic({ tabId: props.tabId }),
                ['activeTab'],
                aiConsentLogic,
                ['dataProcessingAccepted'],
                featureFlagLogic,
                ['featureFlags'],
                preflightLogic,
                ['preflight'],
                teamLogic,
                ['currentTeamId'],
            ],
            actions: [
                dataVisualizationLogic(props.visualizationProps),
                ['setQuery', '_setQuery'],
                outputPaneLogic({ tabId: props.tabId }),
                ['setActiveTab'],
                dataNodeLogic({ key: props.visualizationProps.key, query: props.visualizationProps.query.source }),
                ['loadData', 'loadDataSuccess'],
            ],
        })),
        selectors({
            enabled: [
                (s) => [s.dataProcessingAccepted, s.featureFlags, s.preflight],
                (consent: boolean, flags: FeatureFlagsSet, preflight: PreflightStatus | null): boolean =>
                    consent &&
                    !!flags[FEATURE_FLAGS.JEV_CHART_AUTODETECTION] &&
                    !!(preflight?.is_debug || flags[FEATURE_FLAGS.ML_INFERENCE_DECISIONS]),
            ],
        }),
        loaders(({ values, actions, cache }) => ({
            recommendation: [
                null as ChartRecommendation | null,
                {
                    recommendChart: async (_: void, breakpoint) => {
                        cache.disposables.dispose('chartDecision')
                        // Let the existing column subscription finish setting its fallback axes first.
                        await breakpoint(0)
                        if (!values.enabled || values.currentTeamId === null || values.responseLoading) {
                            return null
                        }
                        const query = values.query
                        const presentation = presentationKey(query, values.activeTab)
                        if (query.display !== ChartDisplayType.Auto && presentation !== cache.lastAppliedPresentation) {
                            return null
                        }
                        const response = values.response
                        const rows: unknown[][] =
                            response && 'results' in response && Array.isArray(response.results) ? response.results : []
                        const columns = values.columns
                        const request = buildChartDecision(columns, rows)
                        if (!request) {
                            return null
                        }
                        const teamId = values.currentTeamId
                        const controller = new AbortController()
                        cache.disposables.add(() => () => controller.abort(), 'chartDecision', {
                            pauseOnPageHidden: false,
                        })
                        try {
                            const result = await withTimeout(
                                decisionsApi.mlInferenceDecisionsDecideCreate(String(teamId), request, {
                                    signal: controller.signal,
                                }),
                                5000
                            )
                            breakpoint()
                            if (
                                controller.signal.aborted ||
                                !values.enabled ||
                                values.currentTeamId !== teamId ||
                                values.response !== response ||
                                values.responseLoading ||
                                JSON.stringify(values.query.source) !== JSON.stringify(query.source) ||
                                presentationKey(values.query, values.activeTab) !== presentation
                            ) {
                                return null
                            }
                            const recommendation = readChartDecision(result, columns, rows)
                            if (!recommendation) {
                                return null
                            }
                            const node: DataVisualizationNode = {
                                ...values.query,
                                display: recommendation.display,
                                chartSettings: recommendation.chartSettings,
                            }
                            cache.fallbackPresentation = {
                                display: query.display,
                                chartSettings: query.chartSettings,
                                tab: values.activeTab,
                            }
                            actions._setQuery(node)
                            actions.setQuery(() => node)
                            actions.setActiveTab(recommendation.outputTab)
                            cache.lastAppliedPresentation = presentationKey(node, recommendation.outputTab)
                            return recommendation
                        } catch {
                            breakpoint()
                            return null
                        } finally {
                            controller.abort()
                        }
                    },
                },
            ],
        })),
        listeners(({ actions, values, cache }) => ({
            loadData: () => {
                cache.disposables.dispose('chartDecision')
                if (
                    cache.lastAppliedPresentation === presentationKey(values.query, values.activeTab) &&
                    cache.fallbackPresentation
                ) {
                    const { display, chartSettings, tab } = cache.fallbackPresentation
                    const node = { ...values.query, display, chartSettings }
                    actions._setQuery(node)
                    actions.setQuery(() => node)
                    actions.setActiveTab(tab)
                }
                cache.lastAppliedPresentation = undefined
            },
            loadDataSuccess: () => actions.recommendChart(),
        })),
    ])
