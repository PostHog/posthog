export const ESTIMATE_DEBOUNCE_MS = 1000

function buildRequest(queryInput: string | null, sourceQuery: DataVisualizationNode): QueryEstimateRequestApi {
    const source = sourceQuery?.source
    return {
        query: (queryInput ?? source?.query ?? '').trim(),
        send_raw_query: !!source?.sendRawQuery,
        variables: source?.variables as QueryEstimateRequestApi['variables'],
        filters: source?.filters as QueryEstimateRequestApi['filters'],
    }
}

