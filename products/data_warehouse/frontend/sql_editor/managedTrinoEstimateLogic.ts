export const managedTrinoEstimateLogic: LogicWrapper<managedTrinoEstimateLogicType> =
    kea<managedTrinoEstimateLogicType>([
        props({} as ManagedTrinoEstimateLogicProps),
        key((props) => props.tabId),
        path((key) => ['products', 'data_warehouse', 'sql_editor', 'managedTrinoEstimateLogic', key]),
        connect((props: ManagedTrinoEstimateLogicProps) => ({
            values: [
                featureFlagLogic,
                ['featureFlags'],
                sqlEditorLogic({ tabId: props.tabId }),
                ['queryInput', 'sourceQuery'],
            ],
            // Every action that can change the query text, its target or its inputs.
            actions: [
                sqlEditorLogic({ tabId: props.tabId }),
                [
                    'setQueryInput',
                    'setExecutionTarget',
                    'setSourceQuery',
                    'setSelectedVariables',
                    'updateTab',
                    'createTab',
                    'editView',
                ],
            ],
        })),
        actions({
            refreshEstimate: true,
            estimateStarted: true,
            estimateLoaded: (estimate: QueryEstimateResponseApi) => ({ estimate }),
            estimateFailed: true,
            estimateCleared: true,
            popoverOpened: true,
        }),
        reducers({
            estimate: [
                null as QueryEstimateResponseApi | null,
                {
                    estimateLoaded: (_, { estimate }) => estimate,
                    estimateFailed: () => null,
                    estimateCleared: () => null,
                },
            ],
            estimateStatus: [
                'idle' as ManagedTrinoEstimateStatus,
                {
                    estimateStarted: () => 'loading',
                    estimateLoaded: () => 'ready',
                    estimateFailed: () => 'error',
                    estimateCleared: () => 'idle',
                },
            ],
        }),
        selectors({
            estimateEnabled: [
                (s) => [s.featureFlags, s.sourceQuery],
                (featureFlags: FeatureFlagsSet, sourceQuery: DataVisualizationNode): boolean =>
                    !!featureFlags[FEATURE_FLAGS.MANAGED_WAREHOUSE_CONSOLE] &&
                    sourceQuery?.source?.executionTarget === 'managed_trino',
            ],
            warnings: [
                (s) => [s.estimate],
                (estimate: QueryEstimateResponseApi | null): EstimateWarning[] =>
                    estimate ? estimateWarnings(estimate) : [],
            ],
        }),
        listeners(({ actions, values, cache }) => {
            const refresh = (): void => {
                actions.refreshEstimate()
            }
            return {
                setQueryInput: refresh,
                setExecutionTarget: refresh,
                setSourceQuery: refresh,
                setSelectedVariables: refresh,
                updateTab: refresh,
                createTab: refresh,
                editView: refresh,
                refreshEstimate: async (_, breakpoint) => {
                    // Without the flag or a managed Trino target there is nothing to estimate and no work to do.
                    if (!values.estimateEnabled) {
                        if (values.estimateStatus !== 'idle') {
                            actions.estimateCleared()
                        }
                        return
                    }
                    await breakpoint(ESTIMATE_DEBOUNCE_MS)
                    const request = buildRequest(values.queryInput, values.sourceQuery)
                    if (!request.query) {
                        actions.estimateCleared()
                        return
                    }
                    const requestKey = JSON.stringify(request)
                    if (requestKey === cache.lastRequestKey && values.estimate) {
                        return
                    }
                    const controller = new AbortController()
                    // A newer run replaces this key, which aborts the request still in flight.
                    cache.disposables.add(() => () => controller.abort(), 'estimate-request', {
                        pauseOnPageHidden: false,
                    })
                    actions.estimateStarted()
                    try {
                        const estimate = await managedWarehouseConsoleEstimateCreate(
                            String(teamLogic.values.currentTeamId),
                            request,
                            { signal: controller.signal }
                        )
                        breakpoint()
                        cache.lastRequestKey = requestKey
                        actions.estimateLoaded(estimate)
                        const resultKey = `${requestKey}|${estimate.upper_bound_bytes}|${estimate.warnings.join(',')}`
                        if (resultKey !== cache.lastCapturedKey) {
                            cache.lastCapturedKey = resultKey
                            posthog.capture('sql editor estimate shown', {
                                bytes_bucket: estimateBytesBucket(estimate.upper_bound_bytes),
                                exceeds_cap: estimate.exceeds_cap,
                                complete: estimate.complete,
                            })
                        }
                    } catch (e) {
                        if (controller.signal.aborted || (e as Error | null)?.name === 'AbortError') {
                            return
                        }
                        // kea's own breakpoint error has to propagate, so a stale run never writes state.
                        breakpoint()
                        cache.lastRequestKey = undefined
                        actions.estimateFailed()
                    }
                },
                popoverOpened: () => {
                    posthog.capture('sql editor estimate popover opened', {
                        tables: values.estimate?.tables.length ?? 0,
                        warnings: values.warnings.map((warning) => warning.kind),
                    })
                },
            }
        }),
        afterMount(({ actions }) => {
            actions.refreshEstimate()
        }),
    ])
