export const enrichmentScoringLogic = kea<enrichmentScoringLogicType>([
    path(['products', 'growth', 'frontend', 'aiEnrichment', 'enrichmentScoringLogic']),
    actions({
        setActiveTab: (activeTab: 'labels' | 'scoring') => ({ activeTab }),
        selectConfig: (config: ScoringConfigApi) => ({ config }),
        setSource: (source: string) => ({ source }),
    }),
    loaders(({ values }) => ({
        configs: [
            null as ScoringConfigListResponseApi | null,
            {
                loadConfigs: async (): Promise<ScoringConfigListResponseApi> =>
                    await growthEnrichmentScoringConfigsRetrieve(),
            },
        ],
        preview: [
            null as FormulaPreview | null,
            {
                previewFormula: async (): Promise<FormulaPreview> => {
                    if (!values.selectedConfig) {
                        throw new Error('Set up the initial scoring configuration before previewing a formula.')
                    }
                    const baseConfigId = values.selectedConfig.id
                    const source = values.source
                    const activeConfigId = values.activeConfig?.id ?? null
                    const response = await growthEnrichmentScoringPreviewCreate({
                        source,
                        sample: 10,
                        base_config_id: baseConfigId,
                    })
                    return { source, activeConfigId, baseConfigId, response }
                },
            },
        ],
        savedConfig: [
            null as ScoringConfigApi | null,
            {
                saveFormula: async (version: string): Promise<ScoringConfigApi> => {
                    if (!values.selectedConfig) {
                        throw new Error('Set up the initial scoring configuration before saving a formula.')
                    }
                    return await growthEnrichmentScoringSaveCreate({
                        source: values.source,
                        version: version.trim(),
                        base_config_id: values.selectedConfig.id,
                    })
                },
            },
        ],
        activatedConfig: [
            null as ScoringConfigApi | null,
            {
                activateFormula: async (id: string): Promise<ScoringConfigApi> =>
                    await growthEnrichmentScoringActivateCreate({ config_id: id }),
            },
        ],
    })),
    reducers({
        activeTab: ['labels' as 'labels' | 'scoring', { setActiveTab: (_, { activeTab }) => activeTab }],
        selectedConfig: [
            null as ScoringConfigApi | null,
            {
                selectConfig: (_, { config }) => config,
                loadConfigsSuccess: (state, { configs }) =>
                    configs.results.find((config) => config.id === state?.id) ?? state,
                activateFormulaSuccess: (state, { activatedConfig }) =>
                    state?.id === activatedConfig.id ? activatedConfig : state,
            },
        ],
        source: [
            '',
            {
                setSource: (_, { source }) => source,
                selectConfig: (_, { config }) => config.source,
            },
        ],
        loadError: [null as string | null, { loadConfigs: () => null, loadConfigsFailure: (_, { error }) => error }],
        actionError: [
            null as string | null,
            {
                previewFormula: () => null,
                previewFormulaFailure: (_, { error }) => error,
                saveFormula: () => null,
                saveFormulaFailure: (_, { error }) => error,
                activateFormula: () => null,
                activateFormulaFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        versions: [
            (s) => [s.configs],
            (configs: ScoringConfigListResponseApi | null): ScoringConfigApi[] => configs?.results ?? [],
        ],
        activeConfig: [
            (s) => [s.versions],
            (versions: ScoringConfigApi[]): ScoringConfigApi | null =>
                versions.find((config) => config.is_active) ?? null,
        ],
        isDirty: [
            (s) => [s.source, s.selectedConfig, s.configs],
            (
                source: string,
                selectedConfig: ScoringConfigApi | null,
                configs: ScoringConfigListResponseApi | null
            ): boolean => source !== (selectedConfig?.source ?? configs?.default_source ?? ''),
        ],
        previewIsStale: [
            (s) => [s.source, s.preview, s.activeConfig, s.selectedConfig],
            (
                source: string,
                preview: FormulaPreview | null,
                activeConfig: ScoringConfigApi | null,
                selectedConfig: ScoringConfigApi | null
            ): boolean =>
                !!preview &&
                (source !== preview.source ||
                    preview.activeConfigId !== (activeConfig?.id ?? null) ||
                    preview.baseConfigId !== selectedConfig?.id),
        ],
        isSaving: [
            (s) => [s.savedConfigLoading, s.activatedConfigLoading],
            (savedConfigLoading: boolean, activatedConfigLoading: boolean): boolean =>
                savedConfigLoading || activatedConfigLoading,
        ],
    }),
    listeners(({ actions, values }) => ({
        loadConfigsSuccess: ({ configs }) => {
            if (!values.selectedConfig && !values.source) {
                const initial = configs.results.find((config) => config.is_active) ?? configs.results[0]
                if (initial) {
                    actions.selectConfig(initial)
                } else {
                    actions.setSource(configs.default_source)
                }
            }
        },
        saveFormulaSuccess: ({ savedConfig }) => {
            actions.selectConfig(savedConfig)
            actions.loadConfigs()
            lemonToast.success('Formula saved. Activate it when you are ready to use it for scoring.')
        },
        activateFormulaSuccess: () => {
            actions.loadConfigs()
            lemonToast.success('Formula activated. Future scoring runs will use this version.')
        },
    })),
    afterMount(({ actions }) => actions.loadConfigs()),
])
