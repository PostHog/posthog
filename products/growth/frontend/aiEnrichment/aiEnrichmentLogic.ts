// The run endpoint streams application/x-ndjson and isn't part of the generated response types
// (backend documents it as a raw string body) - these mirror the row/summary shapes described in
// products/growth/backend/api/ai_enrichment.py's `run` action docstring. `outputs` is keyed by the
// config's output_fields; it is null and `error` is set when that row's classification failed.
export interface AIEnrichmentRunRow {
    company: string
    domain: string | null
    inputs: Record<string, unknown>
    outputs: Record<string, boolean | number | string> | null
    error?: string
    // classify_payload's provenance dict (enrichment/labels.py), verbatim. `skipped` is the
    // authoritative "was this row's verdict skipped" flag - prefer it over sniffing individual
    // output values for the literal "unknown" string, which a schema with no boolean output
    // field never writes at all (see aiEnrichmentResultColumns.ts's isSkippedRow).
    meta?: { skipped?: string }
}

export interface AIEnrichmentRunSummary {
    classified: number
    unknown: number
    errors: number
}

interface AIEnrichmentEditorSnapshot {
    promptText: string
    model: string
    inputFields: string[]
    outputFields: AIEnrichmentOutputField[]
}

const DEFAULT_MODEL = 'gpt-5-mini'

function sameInputFieldSet(a: string[], b: string[]): boolean {
    if (a.length !== b.length) {
        return false
    }
    const sortedA = [...a].sort()
    const sortedB = [...b].sort()
    return sortedA.every((value, index) => value === sortedB[index])
}

function sameOutputFieldSet(a: AIEnrichmentOutputField[], b: AIEnrichmentOutputField[]): boolean {
    if (a.length !== b.length) {
        return false
    }
    const normalize = (fields: AIEnrichmentOutputField[]): string =>
        [...fields]
            .sort((left, right) => left.key.localeCompare(right.key))
            .map((field) => `${field.key}:${field.type}:${field.description}`)
            .join('|')
    return normalize(a) === normalize(b)
}

function safeDecodeURIComponent(value: string): string {
    try {
        return decodeURIComponent(value)
    } catch {
        // Malformed percent-encoding (e.g. a lone "%") - fall back to the raw value rather than
        // crash the whole scene on an unparseable URL.
        return value
    }
}

function configToSnapshot(config: ConfigVersionApi): AIEnrichmentEditorSnapshot {
    return {
        promptText: config.prompt_text,
        model: config.model,
        inputFields: config.input_fields ?? [],
        outputFields: (config.output_fields ?? []).map((field) => ({
            key: field.key,
            type: field.type,
            description: field.description ?? '',
        })),
    }
}

