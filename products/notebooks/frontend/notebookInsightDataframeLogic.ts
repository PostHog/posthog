export const notebookInsightDataframeLogic = kea<notebookInsightDataframeLogicType>([
    props({} as NotebookInsightDataframeLogicProps),
    key((props) => `${props.notebookLogic.key}-${props.nodeId}`),
    path((key) => ['products', 'notebooks', 'notebookInsightDataframeLogic', key]),
    connect((props: NotebookInsightDataframeLogicProps) => ({
        values: [
            props.notebookLogic,
            ['content'],
            notebookNodeSQLV2Logic(insightRunProps(props)),
            ['isRunning', 'runError'],
            notebookOperationsLogic({ shortId: props.notebookLogic.props.shortId }),
            ['isBusy'],
        ],
        actions: [
            insightDataLogic(props.insightProps),
            ['loadDataSuccess as insightLoaded'],
            notebookOperationsLogic({ shortId: props.notebookLogic.props.shortId }),
            ['finishOperation as operationFinished'],
        ],
    })),
    actions({
        syncDataframe: (force: boolean = false) => ({ force }),
        retry: true,
        setReturnVariable: (returnVariable: string) => ({ returnVariable }),
        setSyncing: (syncing: boolean) => ({ syncing }),
        setError: (error: string | null) => ({ error }),
    }),
    reducers({
        syncing: [false, { setSyncing: (_, { syncing }) => syncing }],
        preparationError: [null as string | null, { setError: (_, { error }) => error }],
    }),
    selectors({
        returnVariable: [
            (s) => [
                (_, p: NotebookInsightDataframeLogicProps) => p.attributes.returnVariable,
                s.content,
                (_, p: NotebookInsightDataframeLogicProps) => p.nodeId,
            ],
            (name: string | undefined, content: JSONContent, nodeId: string): string =>
                name ?? buildNotebookDependencyGraph(content).nodesById[nodeId]?.returnVariable ?? 'insight_df',
        ],
        isPreparing: [
            (s) => [s.syncing, s.isRunning],
            (syncing: boolean, running: boolean): boolean => syncing || running,
        ],
        error: [
            (s) => [s.preparationError, s.runError],
            (preparationError: string | null, runError: string | null): string | null => preparationError ?? runError,
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        setReturnVariable: ({ returnVariable }) => props.updateAttributes({ nodeId: props.nodeId, returnVariable }),
        insightLoaded: () => actions.syncDataframe(),
        operationFinished: () => actions.syncDataframe(),
        retry: () => {
            cache.attemptedSource = undefined
            actions.syncDataframe(true)
        },
        syncDataframe: async ({ force }) => {
            if (
                !props.enabled ||
                props.notebookLogic.values.isShared ||
                !props.notebookLogic.values.canEditNotebook ||
                values.isPreparing ||
                values.isBusy ||
                !isReferenceableSqlV2FrameName(values.returnVariable)
            ) {
                return
            }
            const data = insightDataLogic(props.insightProps)
            if (data.values.insightDataLoading || !data.values.query || !data.values.insightData?.result) {
                return
            }
            const sourceKey = (): string =>
                JSON.stringify([data.values.query, data.values.insightData.last_refresh ?? null])
            let source = sourceKey()
            if (
                !force &&
                ((props.attributes.runId && props.attributes.dataframeSource === source) ||
                    cache.attemptedSource === source)
            ) {
                return
            }
            cache.attemptedSource = source
            actions.setSyncing(true)
            actions.setError(null)
            try {
                if (!data.values.hogQL) {
                    const query = dataNodeLogic.findMounted({ key: insightVizDataNodeKey(props.insightProps) })
                    if (!query) {
                        return
                    }
                    await query.asyncActions.loadData('force_async')
                }
                const code = data.values.hogQL
                if (!code) {
                    actions.setError('This insight does not expose a SQL query for its dataframe.')
                    return
                }
                source = sourceKey()
                cache.attemptedSource = source
                const run = notebookNodeSQLV2Logic(insightRunProps(props))
                props.updateAttributes({ nodeId: props.nodeId, returnVariable: values.returnVariable })
                await run.asyncActions.runQuery(code, {})
                if (!run.values.runError) {
                    props.updateAttributes({ dataframeSource: source, dataframeQuery: code })
                }
            } catch {
                actions.setError('Could not prepare this dataframe. Try again.')
            } finally {
                actions.setSyncing(false)
            }
        },
    })),
    afterMount(({ actions }) => actions.syncDataframe()),
    propsChanged(({ actions }) => actions.syncDataframe()),
])
