export interface NotebookInsightDataframeLogicProps {
    notebookLogic: BuiltLogic<notebookLogicType>
    nodeId: string
    insightProps: InsightLogicProps
    attributes: InsightDataframeAttributes
    updateAttributes: (attributes: Partial<InsightDataframeAttributes>) => void
    enabled: boolean
}

function insightRunProps(props: NotebookInsightDataframeLogicProps): NotebookNodeSQLV2LogicProps {
    return {
        nodeId: props.nodeId,
        notebookShortId: props.notebookLogic.props.shortId,
        runId: props.enabled ? props.attributes.runId : undefined,
        hasResult: !!props.attributes.result,
        hasResultMetadata: !!props.attributes.result,
        updateAttributes: props.updateAttributes,
        getContent: () => props.notebookLogic.values.content,
        getVariables: () => props.notebookLogic.values.runnableVariables,
    }
}

