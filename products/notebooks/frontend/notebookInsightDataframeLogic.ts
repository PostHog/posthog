import { BuiltLogic, MakeLogicType, actions, kea, key, listeners, path, props, reducers } from 'kea'

import { lemonToast } from '@posthog/lemon-ui'

import { insightDataLogic } from 'scenes/insights/insightDataLogic'
import type { notebookLogicType } from 'scenes/notebooks/Notebook/notebookLogic'

import { dataNodeLogic } from '~/queries/nodes/DataNode/dataNodeLogic'
import { insightVizDataNodeKey } from '~/queries/nodes/InsightViz/insightVizKeys'
import type { InsightLogicProps } from '~/types'

export interface NotebookInsightDataframeLogicProps {
    notebookLogic: BuiltLogic<notebookLogicType>
    insightProps: InsightLogicProps
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface notebookInsightDataframeLogicValues {
    isCreatingDataframe: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface notebookInsightDataframeLogicActions {
    createDataframe: () => {
        value: true
    }
    setIsCreatingDataframe: (isCreatingDataframe: boolean) => {
        isCreatingDataframe: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface notebookInsightDataframeLogicMeta {
    key: string
}

export type notebookInsightDataframeLogicType = MakeLogicType<
    notebookInsightDataframeLogicValues,
    notebookInsightDataframeLogicActions,
    NotebookInsightDataframeLogicProps,
    notebookInsightDataframeLogicMeta
>

export const notebookInsightDataframeLogic = kea<notebookInsightDataframeLogicType>([
    props({} as NotebookInsightDataframeLogicProps),
    key((props) => `${props.notebookLogic.key}-${props.insightProps.dashboardItemId}`),
    path((key) => ['products', 'notebooks', 'notebookInsightDataframeLogic', key]),
    actions({
        createDataframe: true,
        setIsCreatingDataframe: (isCreatingDataframe: boolean) => ({ isCreatingDataframe }),
    }),
    reducers({
        isCreatingDataframe: [false, { setIsCreatingDataframe: (_, { isCreatingDataframe }) => isCreatingDataframe }],
    }),
    listeners(({ actions, values, props }) => ({
        createDataframe: async () => {
            if (
                values.isCreatingDataframe ||
                !props.notebookLogic.values.canEditNotebook ||
                props.notebookLogic.values.isShared
            ) {
                return
            }
            actions.setIsCreatingDataframe(true)
            try {
                const dataLogic = insightDataLogic(props.insightProps)
                if (!dataLogic.values.hogQL) {
                    const queryLogic = dataNodeLogic.findMounted({ key: insightVizDataNodeKey(props.insightProps) })
                    if (!queryLogic) {
                        lemonToast.error('The insight is still loading. Try again when its results appear.')
                        return
                    }
                    await queryLogic.asyncActions.loadData('force_async')
                }
                const code = dataLogic.values.hogQL
                if (!code) {
                    lemonToast.error(
                        'This insight cannot be converted to a dataframe. Add a SQL cell to query its data.'
                    )
                    return
                }
                props.notebookLogic.actions.insertInsightDataframe(code)
            } catch {
                lemonToast.error('Could not load the insight query. Try again.')
            } finally {
                actions.setIsCreatingDataframe(false)
            }
        },
    })),
])
