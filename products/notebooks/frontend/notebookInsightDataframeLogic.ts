export const notebookInsightDataframeLogic = kea<notebookInsightDataframeLogicType>([
    props({} as NotebookInsightDataframeLogicProps),
    key((props) => `${props.notebookLogic.key}-${props.nodeId}`),
    path((key) => ['products', 'notebooks', 'notebookInsightDataframeLogic', key]),
    connect((props: NotebookInsightDataframeLogicProps) => ({
        values: [
            props.notebookLogic,
            ['content'],
            notebookOperationsLogic({ shortId: props.notebookLogic.props.shortId }),
            ['isBusy'],
        ],
    })),
    actions({
        syncDataframe: (force: boolean = false) => ({ force }),
        prepareDataframe: (force: boolean) => ({ force }),
        retry: true,
        setReturnVariable: (returnVariable: string) => ({ returnVariable }),
        setSyncing: (syncing: boolean) => ({ syncing }),
        setError: (error: string | null, unsupported: boolean = false) => ({ error, unsupported }),
    }),
    reducers({
        isPreparing: [false, { setSyncing: (_, { syncing }) => syncing }],
        error: [null as string | null, { setError: (_, { error }) => error }],
        unsupported: [false, { setError: (_, { unsupported }) => unsupported }],
    }),
    selectors({
        returnVariable: [
            (s) => [
                s.content,
                (_, p: NotebookInsightDataframeLogicProps) => p.nodeId,
                (_, p: NotebookInsightDataframeLogicProps) => p.attributes.returnVariable,
            ],
            (content: JSONContent | null, nodeId: string, name: string | undefined): string =>
                collectNotebookDataframeNodes(content).find((node) => node.nodeId === nodeId)?.returnVariable ??
                name ??
                'insight_df',
        ],
    }),
    listeners(({ actions, asyncActions, values, props, cache }) => ({
        setReturnVariable: ({ returnVariable }) => props.updateAttributes({ nodeId: props.nodeId, returnVariable }),
        retry: () => actions.syncDataframe(true),
        syncDataframe: async ({ force }) => {
            if (!cache.preparation) {
                cache.preparation = asyncActions.prepareDataframe(force)
            }
            try {
                await cache.preparation
            } finally {
                cache.preparation = null
            }
        },
        prepareDataframe: async ({ force }, breakpoint) => {
            if (!props.enabled || props.notebookLogic.values.isShared || !props.notebookLogic.values.canEditNotebook) {
                return
            }
            if (!isReferenceableSqlV2FrameName(values.returnVariable)) {
                actions.setError('Enter a valid dataframe name before using this insight.')
                return
            }
            if (values.isBusy) {
                actions.setError('Wait for the current notebook operation to finish, then try again.')
                return
            }
            const prepare = async (): Promise<void> => {
                actions.setSyncing(true)
                actions.setError(null)
                const operations = notebookOperationsLogic({ shortId: props.notebookLogic.props.shortId })
                const operationId = `${props.nodeId}:prepare`
                operations.actions.startOperation({
                    id: operationId,
                    nodeId: props.nodeId,
                    kind: 'run',
                    label: `Preparing ${values.returnVariable}`,
                })
                try {
                    const mounted = insightDataLogic.findMounted(props.insightProps)
                    let query = (mounted?.values.query ?? props.insightProps.query ?? props.attributes.query) as
                        | QuerySchema
                        | undefined
                    const shortId =
                        props.attributes.id ?? (query?.kind === NodeKind.SavedInsightNode ? query.shortId : undefined)
                    if (shortId) {
                        const insight = await insightsApi.getByShortId(shortId as InsightShortId)
                        query = (insight?.query ?? undefined) as QuerySchema | undefined
                    }
                    if (!query) {
                        actions.setError('The insight query is unavailable. Try again after the insight loads.')
                        return
                    }
                    const source = JSON.stringify(query)
                    const attributes = props.attributes
                    if (
                        !force &&
                        attributes.runId &&
                        attributes.dataframeQuery &&
                        attributes.dataframeSource === source
                    ) {
                        if (cache.completedRunId === attributes.runId) {
                            return
                        }
                        try {
                            const saved = await api.notebooks.sqlV2RunResult(
                                props.notebookLogic.props.shortId,
                                attributes.runId
                            )
                            if (saved.status === 'done') {
                                cache.completedRunId = attributes.runId
                                return
                            }
                        } catch {
                            /* An expired result can be prepared again on demand. */
                        }
                    }
                    let code =
                        mounted?.values.query && JSON.stringify(mounted.values.query) === source
                            ? mounted.values.hogQL
                            : null
                    if (!code) {
                        const sourceQuery = ('source' in query ? query.source : query) as DataNode
                        const response = await performQuery(sourceQuery, undefined, 'async')
                        code =
                            response && 'hogql' in response && typeof response.hogql === 'string'
                                ? response.hogql
                                : null
                    }
                    if (!code) {
                        actions.setError("This insight can't be used as a dataframe.", true)
                        return
                    }
                    const run = await api.notebooks.sqlV2Run(props.notebookLogic.props.shortId, {
                        node_id: props.nodeId,
                        code,
                        refs: {},
                        reuse_results: !force,
                    })
                    for (let attempt = 0; attempt < 600; attempt++) {
                        breakpoint()
                        const response = await api.notebooks.sqlV2RunResult(
                            props.notebookLogic.props.shortId,
                            run.run_id
                        )
                        breakpoint()
                        if (response.status === 'done') {
                            const result = response.result
                            props.updateAttributes({
                                nodeId: props.nodeId,
                                returnVariable: values.returnVariable,
                                runId: run.run_id,
                                runStatus: 'done',
                                dataframeSource: source,
                                dataframeQuery: code,
                                result: result
                                    ? {
                                          columns: result.columns ?? [],
                                          types: result.types ?? [],
                                          row_count: result.row_count ?? 0,
                                          has_more: result.has_more ?? false,
                                      }
                                    : null,
                            })
                            cache.completedRunId = run.run_id
                            return
                        }
                        if (response.status === 'failed' || response.status === 'interrupted') {
                            actions.setError(response.error || 'The dataframe query did not finish. Try again.')
                            return
                        }
                        await breakpoint(1000)
                    }
                    actions.setError('The dataframe is taking too long to prepare. Try again.')
                } catch (error) {
                    if (error instanceof Error && isBreakpoint(error)) {
                        throw error
                    }
                    actions.setError(sqlV2RunErrorMessage(error, 'Could not prepare this dataframe'))
                } finally {
                    actions.setSyncing(false)
                    operations.actions.finishOperation(operationId)
                }
            }
            await prepare()
        },
    })),
])
