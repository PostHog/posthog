export const notebookAppViewerLogic = kea<notebookAppViewerLogicType>([
    props({} as ViewerProps),
    key((props) => props.sessionId),
    path((key) => ['products', 'notebooks', 'appBuilder', 'notebookAppViewerLogic', key]),
    actions({
        changeInput: (name: string, value: NotebookVariableValue) => ({ name, value }),
        setAuto: (auto: boolean) => ({ auto }),
    }),
    loaders(({ props, values, cache }) => ({
        release: [
            null as NotebookAppReleaseApi | null,
            {
                loadRelease: async () => {
                    const controller = new AbortController()
                    cache.disposables.add(() => () => controller.abort(), 'release', { pauseOnPageHidden: false })
                    return await notebooksAppReleaseRetrieve(props.project, props.shortId, {
                        signal: controller.signal,
                    })
                },
            },
        ],
        publishedResults: [
            {} as Record<string, PublishedRunResult>,
            {
                restore: async (
                    release: NotebookAppReleaseApi,
                    breakpoint
                ): Promise<Record<string, PublishedRunResult>> => {
                    const controller = new AbortController()
                    cache.disposables.add(() => () => controller.abort(), 'publishedResults', {
                        pauseOnPageHidden: false,
                    })
                    const results = await restorePublishedResults(props, release, controller)
                    breakpoint()
                    return results
                },
            },
        ],
        results: [
            null as ViewerResults | null,
            {
                refresh: async (force: boolean = false, breakpoint): Promise<ViewerResults> => {
                    const controller = new AbortController()
                    cache.disposables.add(() => () => controller.abort(), 'viewerQueries', { pauseOnPageHidden: false })
                    const { release, variables, results } = values
                    await breakpoint(250)
                    if (!release) {
                        throw new Error('Open a published app before refreshing results.')
                    }
                    const options = { signal: controller.signal }
                    try {
                        const plans = await notebooksAppQueriesCreate(
                            props.project,
                            props.shortId,
                            { revision: release.revision, variables },
                            options
                        )
                        breakpoint()
                        const { outputs, queried } = await resolveViewerOutputs(
                            plans,
                            results?.outputs,
                            props.project,
                            force,
                            controller
                        )
                        breakpoint()
                        if (queried) {
                            const defaults = exposedVariables(release)
                            posthog.capture('notebook app viewer results updated', {
                                short_id: props.shortId,
                                revision: release.revision,
                                filtered: variables.some(
                                    (variable, index) => variable.value !== defaults[index]?.value
                                ),
                            })
                        }
                        return {
                            outputs,
                            variables,
                            updatedAt: queried ? new Date().toISOString() : results?.updatedAt || '',
                        }
                    } catch (error) {
                        controller.abort()
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        variables: [
            [] as NotebookVariable[],
            {
                loadReleaseSuccess: (_, { release }) => exposedVariables(release),
                changeInput: (variables, { name, value }) =>
                    variables.map((v) =>
                        v.name === name ? { ...v, value: coerceNotebookVariableValue(v.type, value) } : v
                    ),
            },
        ],
        auto: [true, { setAuto: (_, { auto }) => auto }],
        releaseFailed: [false, { loadRelease: () => false, loadReleaseFailure: () => true }],
        refreshFailed: [false, { refresh: () => false, refreshFailure: () => true }],
    }),
    selectors({
        dirty: [
            (s) => [s.variables, s.results, s.release],
            (
                variables: NotebookVariable[],
                results: ViewerResults | null,
                release: NotebookAppReleaseApi | null
            ): boolean => {
                const applied = results?.variables ?? (release ? exposedVariables(release) : [])
                return variables.some((v, index) => v.value !== applied[index]?.value)
            },
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadReleaseSuccess: ({ release }) => {
            actions.restore(release)
            posthog.capture('notebook app viewed', { short_id: props.shortId, revision: release.revision })
        },
        changeInput: () => {
            if (values.auto) {
                actions.refresh()
            }
        },
        setAuto: ({ auto }) => {
            if (auto && values.dirty) {
                actions.refresh()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRelease()
    }),
])
