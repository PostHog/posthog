export interface ViewerProps {
    shortId: string
    project: string
    sessionId: string
}
export interface ViewerOutput {
    query: string
    result: HogQLQueryResponse
    generation: number
}
export interface ViewerResults {
    outputs: Record<string, ViewerOutput>
    variables: NotebookVariable[]
    updatedAt: string
}

function exposedVariables(release: NotebookAppReleaseApi): NotebookVariable[] {
    return parseNotebookVariables(release.variables).filter((variable) =>
        release.layout.blocks.some((block) => block.kind === 'input' && block.variable === variable.name)
    )
}

async function executeViewerQuery(
    query: string,
    project: string,
    controller: AbortController,
    force: boolean
): Promise<HogQLQueryResponse> {
    const queryId = uuid()
    const cancel = (): void => {
        void api
            .cancelQuery(queryId, Number(project))
            .catch((error) => console.warn('Failed cancelling viewer query', error))
    }
    controller.signal.addEventListener('abort', cancel, { once: true })
    try {
        return await performQuery<HogQLQuery>(
            { kind: NodeKind.HogQLQuery, query },
            { signal: controller.signal, queryTelemetry: 'metadata' },
            force ? 'force_blocking' : 'blocking',
            queryId
        )
    } finally {
        controller.signal.removeEventListener('abort', cancel)
    }
}

async function resolveViewerOutputs(
    plans: NotebookAppViewerQueryApi[],
    previousOutputs: Record<string, ViewerOutput> | undefined,
    project: string,
    force: boolean,
    controller: AbortController
): Promise<{ outputs: Record<string, ViewerOutput>; queried: boolean }> {
    const outputs: Record<string, ViewerOutput> = {}
    const queries = new ConcurrencyController(4)
    const pending: Promise<void>[] = []
    for (const plan of plans) {
        const previous = previousOutputs?.[plan.node_id]
        if (!force && !previous && plan.matches_defaults) {
            continue
        }
        if (!force && previous?.query === plan.query) {
            outputs[plan.node_id] = previous
            continue
        }
        pending.push(
            queries.run({
                abortController: controller,
                fn: async () => {
                    const result = await executeViewerQuery(plan.query, project, controller, force)
                    outputs[plan.node_id] = { query: plan.query, result, generation: (previous?.generation ?? 0) + 1 }
                },
            })
        )
    }
    await Promise.all(pending)
    return { outputs, queried: pending.length > 0 }
}

