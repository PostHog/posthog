export const notebookAppLogic: LogicWrapper<notebookAppLogicType> = kea<notebookAppLogicType>([
    props({} as NotebookAppLogicProps),
    key(({ shortId }) => shortId),
    path((key) => ['products', 'notebooks', 'notebookAppLogic', key]),
    connect(({ shortId }: NotebookAppLogicProps) => ({
        values: [
            notebookLogic({ shortId }),
            ['markdownEditorValue', 'variables', 'canEditNotebook', 'notebook', 'isTemplate'],
        ],
    })),
    actions({
        changeLayout: (layout: NotebookAppLayoutApi) => ({ layout }),
        selectBlock: (id: string | null) => ({ id }),
        selectTab: (id: string) => ({ id }),
        setPreview: (preview: boolean) => ({ preview }),
        addBlock: (kind: NotebookAppBlockApi['kind'], patch: Partial<NotebookAppBlockApi> = {}) => ({ kind, patch }),
        addCell: (nodeId: string) => ({ nodeId }),
        updateBlock: (id: string, patch: Partial<NotebookAppBlockApi>) => ({ id, patch }),
        removeBlock: (id: string) => ({ id }),
        duplicateBlock: (id: string) => ({ id }),
        moveBlock: (id: string, beforeId: string) => ({ id, beforeId }),
        moveBlockBy: (id: string, direction: number) => ({ id, direction }),
        addTab: true,
        removeTab: (id: string) => ({ id }),
        useNotebookLayout: true,
        undo: true,
        redo: true,
        setInputValue: (name: string, value: NotebookVariableValue) => ({ name, value }),
        openSource: (nodeId: string) => ({ nodeId }),
    }),
    loaders(({ props, values }) => ({
        savedNotebook: [
            null as NotebookApi | null,
            {
                loadApp: async () => notebooksRetrieve(String(ApiConfig.getCurrentTeamId()), props.shortId),
                saveApp: async (publish: boolean = false) => {
                    if (!values.canEditNotebook || values.isTemplate) {
                        throw new Error('This notebook is read-only.')
                    }
                    const source = notebookLogic({ shortId: props.shortId })
                    if (source.values.notebookLoading || source.values.localContent !== null) {
                        throw new Error('Wait for the notebook to finish saving, then try again.')
                    }
                    const result = await notebooksPartialUpdate(String(ApiConfig.getCurrentTeamId()), props.shortId, {
                        app_revision: values.savedNotebook?.app_revision ?? 0,
                        app_draft: values.layout,
                        ...(publish ? { app_published: values.layout } : {}),
                    })
                    posthog.capture(publish ? 'notebook app published' : 'notebook app saved', {
                        short_id: props.shortId,
                        component_count: values.layout.blocks.length,
                        tab_count: values.layout.tabs.length,
                    })
                    lemonToast.success(publish ? 'App layout published' : 'App draft saved')
                    return result
                },
                unpublishApp: async () => {
                    const result = await notebooksPartialUpdate(String(ApiConfig.getCurrentTeamId()), props.shortId, {
                        app_revision: values.savedNotebook?.app_revision ?? 0,
                        app_published: null,
                    })
                    posthog.capture('notebook app unpublished', { short_id: props.shortId })
                    return result
                },
            },
        ],
    })),
    reducers({
        history: [
            { past: [] as NotebookAppLayoutApi[], current: emptyAppLayout(), future: [] as NotebookAppLayoutApi[] },
            {
                changeLayout: (state, { layout }) => ({
                    past: [...state.past, state.current].slice(-50),
                    current: layout,
                    future: [],
                }),
                loadAppSuccess: (_, { savedNotebook }) => ({
                    past: [],
                    current: savedNotebook.app_draft ?? emptyAppLayout(),
                    future: [],
                }),
                saveAppSuccess: (state, { savedNotebook }) => ({
                    ...state,
                    current: savedNotebook.app_draft ?? emptyAppLayout(),
                }),
                undo: (state) =>
                    state.past.length
                        ? {
                              past: state.past.slice(0, -1),
                              current: state.past[state.past.length - 1],
                              future: [...state.future, state.current],
                          }
                        : state,
                redo: (state) =>
                    state.future.length
                        ? {
                              past: [...state.past, state.current],
                              current: state.future[state.future.length - 1],
                              future: state.future.slice(0, -1),
                          }
                        : state,
            },
        ],
        selectedBlockId: [null as string | null, { selectBlock: (_, { id }) => id, selectTab: () => null }],
        activeTabId: [
            'overview',
            {
                selectTab: (_, { id }) => id,
                loadAppSuccess: (_, { savedNotebook }) => savedNotebook.app_draft?.tabs[0]?.id ?? 'overview',
            },
        ],
        preview: [false, { setPreview: (_, { preview }) => preview }],
        error: [
            null as string | null,
            {
                loadApp: () => null,
                saveApp: () => null,
                loadAppFailure: (_, { error }) => error,
                saveAppFailure: (_, { error }) => error,
                unpublishAppFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        layout: [
            (s) => [s.history],
            (history: notebookAppLogicValues['history']): NotebookAppLayoutApi => history.current,
        ],
        cells: [(s) => [s.markdownEditorValue], (markdown: string): NotebookBlockNode[] => appSourceCells(markdown)],
        selectedBlock: [
            (s) => [s.layout, s.selectedBlockId],
            (layout: NotebookAppLayoutApi, id: string | null): NotebookAppBlockApi | null =>
                layout.blocks.find((block) => block.id === id) ?? null,
        ],
        dirty: [
            (s) => [s.layout, s.savedNotebook],
            (layout: NotebookAppLayoutApi, savedNotebook: NotebookApi | null): boolean =>
                JSON.stringify(layout) !== JSON.stringify(savedNotebook?.app_draft ?? emptyAppLayout()),
        ],
        activeTab: [
            (s) => [s.layout, s.activeTabId],
            (layout: NotebookAppLayoutApi, id: string): string =>
                layout.tabs.some((tab) => tab.id === id) ? id : layout.tabs[0].id,
        ],
    }),
    listeners(({ values, actions, props }) => ({
        changeLayout: () => {
            posthog.capture('notebook app layout changed', { short_id: props.shortId })
        },
        setPreview: ({ preview }) => {
            posthog.capture('notebook app preview toggled', { short_id: props.shortId, preview })
        },
        addBlock: ({ kind, patch }) => {
            if (values.layout.blocks.length >= 100) {
                return
            }
            const block = newAppBlock(kind, values.activeTab, patch)
            actions.changeLayout({ ...values.layout, blocks: [...values.layout.blocks, block] })
            actions.selectBlock(block.id)
        },
        addCell: ({ nodeId }) => {
            const cell = values.cells.find((node) => node.id === nodeId)
            if (!cell) {
                return
            }
            const pinned = pinAppCell(values.markdownEditorValue, nodeId)
            if (pinned.markdown !== values.markdownEditorValue) {
                notebookLogic({ shortId: props.shortId }).actions.handleMarkdownEditorChange(pinned.markdown)
                notebookLogic({ shortId: props.shortId }).actions.saveNotebookNow()
            }
            actions.addBlock('cell', { node_id: pinned.nodeId, title: appCellTitle(cell), display: 'output' })
        },
        updateBlock: ({ id, patch }) =>
            actions.changeLayout({
                ...values.layout,
                blocks: values.layout.blocks.map((block) => (block.id === id ? { ...block, ...patch } : block)),
            }),
        removeBlock: ({ id }) => {
            actions.changeLayout({ ...values.layout, blocks: values.layout.blocks.filter((block) => block.id !== id) })
            actions.selectBlock(null)
        },
        duplicateBlock: ({ id }) => {
            const block = values.layout.blocks.find((item) => item.id === id)
            if (block) {
                actions.addBlock(block.kind, { ...block, id: uuid() })
            }
        },
        moveBlock: ({ id, beforeId }) => actions.changeLayout(moveAppBlock(values.layout, id, beforeId)),
        moveBlockBy: ({ id, direction }) => {
            const blocks = values.layout.blocks.filter((block) => block.tab_id === values.activeTab)
            const index = blocks.findIndex((block) => block.id === id)
            const target = blocks[index + direction]
            if (target) {
                direction < 0 ? actions.moveBlock(id, target.id) : actions.moveBlock(target.id, id)
            }
        },
        addTab: () => {
            if (values.layout.tabs.length >= 20) {
                return
            }
            const id = uuid()
            actions.changeLayout({
                ...values.layout,
                tabs: [...values.layout.tabs, { id, title: `Tab ${values.layout.tabs.length + 1}` }],
            })
            actions.selectTab(id)
        },
        removeTab: ({ id }) => {
            if (values.layout.tabs.length === 1) {
                return
            }
            LemonDialog.open({
                title: 'Remove this tab?',
                description: 'Its components will be removed from the app. Notebook cells are kept.',
                primaryButton: {
                    children: 'Remove tab',
                    status: 'danger',
                    onClick: () =>
                        actions.changeLayout({
                            ...values.layout,
                            tabs: values.layout.tabs.filter((tab) => tab.id !== id),
                            blocks: values.layout.blocks.filter((block) => block.tab_id !== id),
                        }),
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        useNotebookLayout: () => {
            let markdown = values.markdownEditorValue
            const blocks = values.cells.slice(0, 100).map((cell) => {
                const pinned = pinAppCell(markdown, cell.id)
                markdown = pinned.markdown
                return newAppBlock('cell', values.activeTab, {
                    node_id: pinned.nodeId,
                    title: appCellTitle(cell),
                    display: 'output',
                })
            })
            notebookLogic({ shortId: props.shortId }).actions.handleMarkdownEditorChange(markdown)
            notebookLogic({ shortId: props.shortId }).actions.saveNotebookNow()
            actions.changeLayout({ ...values.layout, blocks })
        },
        setInputValue: ({ name, value }) => {
            if (!values.canEditNotebook || values.isTemplate) {
                return
            }
            notebookLogic({ shortId: props.shortId }).actions.setVariables(
                values.variables.map((variable) => (variable.name === name ? { ...variable, value } : variable))
            )
            posthog.capture('notebook app input changed', { short_id: props.shortId })
        },
        openSource: ({ nodeId }) => router.actions.push(urls.notebook(props.shortId), {}, { node: nodeId }),
    })),
    afterMount(({ actions, props }) => {
        actions.loadApp()
        posthog.capture('notebook app opened', { short_id: props.shortId })
    }),
    beforeUnload(({ values }) => ({
        enabled: (newLocation?: CombinedLocation) =>
            values.dirty && newLocation?.pathname !== router.values.location.pathname,
        message: 'Leave this notebook? Unsaved app layout changes will be discarded.',
    })),
])
