const KNOWN_ERRORS: AskForChangeError[] = ['repository_not_connected', 'tasks_unavailable']

// The API refuses a request past these limits, so the form checks them before it sends anything.
export const NOTE_MAX_LENGTH = 4000
export const MAX_CHANGES = 50
export const CHANGE_PATH_MAX_LENGTH = 500

/** The field values the person filled in, as the request's `changes`. */
export function filledChanges(fieldValues: Record<string, string>): { path: string; value: string }[] {
    return Object.entries(fieldValues)
        .filter(([, value]) => value.trim() !== '')
        .map(([path, value]) => ({ path, value }))
}

/** What the person has to fix before the request can be sent, by form field. */
export function changeRequestErrors({ note, values }: AskForChangeFormValues): {
    note?: string
    values?: string
} {
    const changes = filledChanges(values)
    return {
        note: !note.trim()
            ? 'Describe the change you want.'
            : note.length > NOTE_MAX_LENGTH
              ? `Shorten the description to ${NOTE_MAX_LENGTH.toLocaleString('en-US')} characters or fewer. It has ${note.length.toLocaleString('en-US')}.`
              : undefined,
        values:
            changes.length > MAX_CHANGES
                ? `Fill in at most ${MAX_CHANGES} values. Describe the other changes in the description.`
                : changes.some(({ path }) => path.length > CHANGE_PATH_MAX_LENGTH)
                  ? `A field path is longer than ${CHANGE_PATH_MAX_LENGTH} characters. Clear its value and describe that change in the description.`
                  : undefined,
    }
}

/** The form behind "Ask for a change": it starts a cloud task that edits the definition and opens a pull request. */
export const askForChangeLogic = kea<askForChangeLogicType>([
    props({} as AskForChangeLogicProps),
    key((props) => props.binding.id),
    path((key) => ['products', 'stacks', 'frontend', 'askForChangeLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentTeam']] })),
    actions({
        setStartedTask: (task: StartedChangeRequestApi) => ({ task }),
        setStartError: (error: AskForChangeError | null, detail: string | null = null) => ({ error, detail }),
    }),
    reducers({
        startedTask: [null as StartedChangeRequestApi | null, { setStartedTask: (_, { task }) => task }],
        startError: [
            null as AskForChangeError | null,
            { setStartError: (_, { error }) => error, submitChangeRequest: () => null },
        ],
        startErrorDetail: [
            null as string | null,
            { setStartError: (_, { detail }) => detail, submitChangeRequest: () => null },
        ],
    }),
    forms(({ actions, props, values }) => ({
        changeRequest: {
            defaults: { note: '', values: {} } as AskForChangeFormValues,
            // kea-forms types the `values` error as a map per key, but one message for the whole group renders under
            // its field, and the runtime accepts a string at any depth.
            errors: (form) => changeRequestErrors(form) as DeepPartialMap<AskForChangeFormValues, ValidationErrorType>,
            submit: async ({ note, values: fieldValues }) => {
                const projectId = values.currentTeam?.project_id
                if (!projectId) {
                    actions.setStartError('other')
                    return
                }
                const changes = filledChanges(fieldValues)
                try {
                    const task = await stacksChangeRequestCreate(
                        String(projectId),
                        props.binding.stack_name,
                        props.binding.id,
                        { note: note.trim(), changes }
                    )
                    actions.setStartedTask(task)
                    // pinned: analytics event name and properties, renaming breaks dashboards
                    posthog.capture('managed in code change requested', {
                        kind: props.binding.kind,
                        entry_point: props.entryPoint,
                        change_count: changes.length,
                    })
                } catch (error: any) {
                    const code = KNOWN_ERRORS.find((known) => known === error?.code) ?? 'other'
                    actions.setStartError(code, typeof error?.detail === 'string' ? error.detail : null)
                    posthog.capture('managed in code change request failed', {
                        kind: props.binding.kind,
                        entry_point: props.entryPoint,
                        code: error?.code ?? null,
                    })
                }
            },
        },
    })),
])
