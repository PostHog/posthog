export type managedEntityLogicType = MakeLogicType<
    managedEntityLogicValues,
    managedEntityLogicActions,
    ManagedEntityLogicProps,
    managedEntityLogicMeta
>

const isMissing = (entityId: ManagedEntityLogicProps['entityId']): boolean =>
    entityId === null || entityId === undefined || entityId === '' || entityId === 'new'

/**
 * Whether a stack manages one entity, by what, and which of its fields code owns.
 * A project with no stack makes one request in total, for `managed_kinds`, and looks up no entity.
 */
export const managedEntityLogic = kea<managedEntityLogicType>([
    props({} as ManagedEntityLogicProps),
    key((props) => `${props.kind}/${props.entityId ?? ''}`),
    path((key) => ['products', 'stacks', 'frontend', 'managedEntityLogic', key]),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeam'],
            featureFlagLogic,
            ['featureFlags'],
            managedKindsLogic,
            ['managedKindNames', 'managedKindsLoading', 'managedKindsFailed'],
        ],
    })),
    actions({
        lookUpBinding: true,
        lookUpBindingSuccess: (binding: BindingApi | null) => ({ binding }),
        lookUpBindingFailure: true,
        detach: true,
        detachSuccess: true,
        detachFailure: true,
        start: true,
    }),
    reducers({
        binding: [
            null as BindingApi | null,
            {
                lookUpBindingSuccess: (_, { binding }) => binding,
                detachSuccess: () => null,
            },
        ],
        bindingState: [
            'unknown' as 'unknown' | 'loaded' | 'failed',
            {
                lookUpBindingSuccess: () => 'loaded',
                lookUpBindingFailure: () => 'failed',
            },
        ],
        detaching: [false, { detach: () => true, detachSuccess: () => false, detachFailure: () => false }],
    }),
    selectors({
        enabled: [(s) => [s.featureFlags], (featureFlags): boolean => !!featureFlags[FEATURE_FLAGS.POSTHOG_AS_CODE]],
        projectId: [
            (s) => [s.currentTeam],
            (currentTeam): string | null => (currentTeam?.project_id ? String(currentTeam.project_id) : null),
        ],
        isManaged: [(s) => [s.binding], (binding): boolean => !!binding && binding.status !== 'detached'],
        managedState: [
            (s) => [s.enabled, (_, props) => props.entityId, s.bindingState, s.isManaged],
            (enabled, entityId, bindingState, isManaged): ManagedEntityState => {
                if (!enabled || isMissing(entityId)) {
                    return 'unmanaged'
                }
                if (bindingState === 'unknown') {
                    return 'unknown'
                }
                if (bindingState === 'failed') {
                    return 'failed'
                }
                return isManaged ? 'managed' : 'unmanaged'
            },
        ],
        ownedFields: [
            (s) => [s.binding],
            (binding): string[] => (binding && binding.status !== 'detached' ? binding.owned_fields : []),
        ],
        ownedFieldDisabledReason: [
            (s) => [s.binding, s.ownedFields],
            (binding, ownedFields) =>
                (path: string): string | null =>
                    binding && isPathOwned(ownedFields, path) ? ownedFieldReason(binding) : null,
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        // The flag and the team can arrive after the scene mounts, so try again when either one does.
        start: () => {
            if (cache.started || !values.enabled || !values.projectId || isMissing(props.entityId)) {
                return
            }
            cache.started = true
            const { managedKindNames, managedKindsLoading, managedKindsFailed } = values
            if (managedKindNames) {
                if (managedKindNames.has(props.kind)) {
                    actions.lookUpBinding()
                } else {
                    actions.lookUpBindingSuccess(null)
                }
            } else if (!managedKindsLoading) {
                // One extra mount that is never released keeps the answer past this scene, so the kinds are read once
                // per session and not once per scene. A read that failed already holds that mount and is retried here.
                if (!managedKindsFailed) {
                    managedKindsLogic.mount()
                }
                managedKindsLogic.actions.loadManagedKinds()
            }
        },
        [teamLogic.actionTypes.loadCurrentTeamSuccess]: () => actions.start(),
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => actions.start(),
        lookUpBinding: async () => {
            const projectId = values.projectId
            if (!projectId || isMissing(props.entityId)) {
                return
            }
            try {
                // A natural-key kind's binding can hold either its id or its name, and the lookup matches its key, which is
                // always the name. So the name finds it in one request whatever the binding holds.
                const entityId = props.naturalId || String(props.entityId)
                const { binding } = await stacksBindingLookup(projectId, { kind: props.kind, entity_id: entityId })
                actions.lookUpBindingSuccess(binding)
                if (binding) {
                    // pinned: analytics event name and properties, renaming breaks dashboards
                    posthog.capture('managed in code banner viewed', {
                        kind: props.kind,
                        has_source_file: !!binding.source?.file,
                        owned_field_count: binding.owned_fields.length,
                    })
                }
            } catch {
                actions.lookUpBindingFailure()
            }
        },
        [managedKindsLogic.actionTypes.loadManagedKindsSuccess]: ({
            managedKinds,
        }: {
            managedKinds: ManagedKindApi[]
        }) => {
            if (managedKinds.some((row) => row.kind === props.kind)) {
                actions.lookUpBinding()
            } else {
                actions.lookUpBindingSuccess(null)
            }
        },
        [managedKindsLogic.actionTypes.loadManagedKindsFailure]: () => {
            actions.lookUpBindingFailure()
        },
        detach: async () => {
            const { binding, projectId } = values
            if (!binding || !projectId) {
                actions.detachFailure()
                return
            }
            try {
                await stacksBindingDetach(projectId, binding.stack_name, binding.id)
                actions.detachSuccess()
                // pinned: analytics event name and properties, renaming breaks dashboards
                posthog.capture('managed in code detached', { kind: props.kind })
                lemonToast.success(`Detached. You can now edit every field of this ${kindLabel(props.kind)} here.`)
            } catch (error: any) {
                actions.detachFailure()
                posthog.capture('managed in code detach failed', { kind: props.kind, code: error?.code ?? null })
                lemonToast.error(`Couldn't detach this ${kindLabel(props.kind)}. ${error?.detail ?? 'Try again.'}`)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.start()
    }),
])
