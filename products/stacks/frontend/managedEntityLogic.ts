export interface ManagedEntityLogicProps {
    /** The definition kind, such as `flag` or `insight`. */
    kind: string
    /** The entity's id. Nothing is looked up while it is empty, as for an entity not saved yet. */
    entityId: string | number | null | undefined
    /** The entity's name, for a natural-key kind such as `event`. The lookup uses it in place of the id. */
    naturalId?: string | null
}

/** `unknown` until both reads answer, so a scene never flashes the banner or a lock. */
export type ManagedEntityState = 'unknown' | 'managed' | 'unmanaged' | 'failed'

