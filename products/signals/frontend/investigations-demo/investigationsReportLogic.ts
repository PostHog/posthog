import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'

import { ReportFixPhase } from './types'

/** Checklist stepped through while the demo generates the code change. */
export const REPORT_GENERATION_STEPS = [
    'Reading PaymentTokenValidator.ts and the a3f9c21 diff',
    'Writing the fallback restoration (+4 lines)',
    'Patching the silent catch block in CheckoutForm.tsx:167',
    'Running the payments test suite, 214 passing',
    'Preparing the diff for review',
]

export type ReportTimelineColor = 'danger' | 'muted' | 'success'

export interface ReportTimelineRow {
    label: string
    time: string
    /** Mono chip at the end of the row, e.g. a commit sha or a duration */
    chip: string
    color: ReportTimelineColor
}

const GENERATION_TICK_MS = 900
const COMMIT_DELAY_MS = 4500

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface investigationsReportLogicValues {
    agentName: string | null
    codeOpen: boolean
    evidenceExpanded: boolean
    generationStep: number
    phase: ReportFixPhase
    prModalOpen: boolean
    timeline: ReportTimelineRow[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface investigationsReportLogicActions {
    advanceGeneration: () => {
        value: true
    }
    launch: () => {
        value: true
    }
    markCommitted: () => {
        value: true
    }
    markProposed: () => {
        value: true
    }
    sendToAgent: (agentName: string) => {
        agentName: string
    }
    setPrModalOpen: (prModalOpen: boolean) => {
        prModalOpen: boolean
    }
    startGeneration: () => {
        value: true
    }
    toggleCode: () => {
        value: true
    }
    toggleEvidence: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface investigationsReportLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        timeline: (phase: ReportFixPhase, agentName: string | null) => ReportTimelineRow[]
    }
}

export type investigationsReportLogicType = MakeLogicType<
    investigationsReportLogicValues,
    investigationsReportLogicActions,
    Record<string, any>,
    investigationsReportLogicMeta
>

/**
 * Fix lifecycle for the demo investigation report: PostHog AI writes the change
 * (generating, proposed) or an external coding agent does (sent, committed), and
 * either path can be launched behind the flag. All mock, nothing is created.
 */
export const investigationsReportLogic = kea<investigationsReportLogicType>([
    path(['products', 'signals', 'frontend', 'investigations-demo', 'investigationsReportLogic']),
    actions({
        startGeneration: true,
        advanceGeneration: true,
        markProposed: true,
        sendToAgent: (agentName: string) => ({ agentName }),
        markCommitted: true,
        launch: true,
        setPrModalOpen: (prModalOpen: boolean) => ({ prModalOpen }),
        toggleCode: true,
        toggleEvidence: true,
    }),
    reducers({
        phase: [
            'reported' as ReportFixPhase,
            {
                startGeneration: (): ReportFixPhase => 'generating',
                markProposed: (): ReportFixPhase => 'proposed',
                sendToAgent: (): ReportFixPhase => 'sent',
                markCommitted: (): ReportFixPhase => 'committed',
                launch: (): ReportFixPhase => 'launched',
            },
        ],
        generationStep: [
            0,
            {
                startGeneration: () => 0,
                advanceGeneration: (state) => state + 1,
            },
        ],
        agentName: [
            null as string | null,
            {
                sendToAgent: (_, { agentName }) => agentName,
            },
        ],
        prModalOpen: [
            false,
            {
                setPrModalOpen: (_, { prModalOpen }) => prModalOpen,
                startGeneration: () => false,
            },
        ],
        codeOpen: [
            false,
            {
                toggleCode: (state) => !state,
            },
        ],
        evidenceExpanded: [
            false,
            {
                toggleEvidence: (state) => !state,
            },
        ],
    }),
    selectors({
        timeline: [
            (s) => [s.phase, s.agentName],
            (phase: ReportFixPhase, agentName: string | null): ReportTimelineRow[] => {
                const rows: ReportTimelineRow[] = [
                    { label: 'Deploy ships strict validation', time: 'Aug 14 09:12', chip: 'a3f9c21', color: 'danger' },
                    { label: 'First TOKEN_EXPIRED failure', time: 'Aug 14 09:16', chip: '+4 min', color: 'muted' },
                    { label: 'Error volume passes 4× baseline', time: 'Aug 15', chip: '4×', color: 'muted' },
                    { label: 'Anomaly detected, case opened', time: 'Aug 16 14:32', chip: 'auto', color: 'muted' },
                    { label: 'Report published', time: 'Aug 16 15:03', chip: '31 min', color: 'success' },
                ]
                if (agentName) {
                    rows.push({
                        label: `Handed off to ${agentName}`,
                        time: 'Aug 16 15:20',
                        chip: 'context',
                        color: 'muted',
                    })
                } else if (['generating', 'proposed', 'launched'].includes(phase)) {
                    rows.push({
                        label: 'Code change generated for review',
                        time: 'Aug 16 15:22',
                        chip: 'opus',
                        color: 'muted',
                    })
                }
                if (agentName && ['committed', 'launched'].includes(phase)) {
                    rows.push({
                        label: 'Commit detected on fix/inv-0247',
                        time: 'Aug 16 16:41',
                        chip: '9d2e4b7',
                        color: 'success',
                    })
                }
                if (phase === 'launched') {
                    rows.push({
                        label: 'Launched at 10% · monitoring',
                        time: 'Aug 18 09:00',
                        chip: '10%',
                        color: 'success',
                    })
                }
                return rows
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        startGeneration: () => {
            cache.disposables.add(() => {
                const timer = window.setInterval(() => actions.advanceGeneration(), GENERATION_TICK_MS)
                return () => clearInterval(timer)
            }, 'generation')
        },
        advanceGeneration: () => {
            if (values.generationStep >= REPORT_GENERATION_STEPS.length) {
                cache.disposables.dispose('generation')
                actions.markProposed()
            }
        },
        sendToAgent: () => {
            cache.disposables.add(() => {
                const timer = window.setTimeout(() => actions.markCommitted(), COMMIT_DELAY_MS)
                return () => clearTimeout(timer)
            }, 'commit')
        },
    })),
    afterMount(({ actions }) => {
        // The inbox and focus pages deep-link here with #fix to start the fix flow straight away.
        if (window.location.hash === '#fix') {
            router.actions.replace(router.values.location.pathname, router.values.searchParams, {})
            actions.startGeneration()
        }
    }),
])
