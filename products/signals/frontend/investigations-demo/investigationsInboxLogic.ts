/** Mock-data state for the investigations inbox redesign preview. Nothing here talks to the backend. */
export const investigationsInboxLogic = kea<investigationsInboxLogicType>([
    path(['products', 'signals', 'frontend', 'investigations-demo', 'investigationsInboxLogic']),
    actions({
        setFilter: (filter: InboxDemoFilter) => ({ filter }),
        setSort: (sort: InboxDemoSort) => ({ sort }),
        toggleRowExpanded: (id: string) => ({ id }),
        openPrModal: (flagKey: string) => ({ flagKey }),
        closePrModal: true,
        confirmPrModal: true,
        tickLiveActivity: true,
    }),
    reducers({
        filter: ['all' as InboxDemoFilter, { setFilter: (_, { filter }) => filter }],
        sort: ['impact' as InboxDemoSort, { setSort: (_, { sort }) => sort }],
        expandedRowId: [
            null as string | null,
            { toggleRowExpanded: (current, { id }) => (current === id ? null : id) },
        ],
        prModalFlagKey: [
            null as string | null,
            {
                openPrModal: (_, { flagKey }) => flagKey,
                closePrModal: () => null,
                confirmPrModal: () => null,
            },
        ],
        liveActivityIndex: [0, { tickLiveActivity: (index) => index + 1 }],
    }),
    selectors({
        filteredInvestigations: [
            (s) => [s.filter, s.sort],
            (filter: InboxDemoFilter, sort: InboxDemoSort): DemoInvestigation[] =>
                DEMO_INVESTIGATIONS.filter((investigation) => matchesFilter(investigation, filter)).sort((a, b) =>
                    sort === 'recency' ? a.ageHours - b.ageHours : b.impactWeight - a.impactWeight
                ),
        ],
        liveActivityPhrase: [
            (s) => [s.liveActivityIndex],
            (index: number): string => LIVE_ACTIVITY_PHRASES[index % LIVE_ACTIVITY_PHRASES.length],
        ],
    }),
    listeners({
        confirmPrModal: () => {
            // The report page reads the `#fix` hash and starts its fix flow on arrival.
            router.actions.push(`${urls.investigationsDemoReport(DEMO_REPORT_ID)}#fix`)
        },
    }),
    afterMount(({ actions, cache }) => {
        cache.disposables.add(() => {
            const timer = window.setInterval(() => actions.tickLiveActivity(), LIVE_ACTIVITY_INTERVAL_MS)
            return () => clearInterval(timer)
        })
    }),
])
