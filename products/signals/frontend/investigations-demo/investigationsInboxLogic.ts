import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'

import { urls } from 'scenes/urls'

import { DEMO_INVESTIGATIONS, DEMO_REPORT_ID, LIVE_ACTIVITY_PHRASES } from './mockData'
import { DemoInvestigation, InboxDemoFilter, InboxDemoSort } from './types'

const LIVE_ACTIVITY_INTERVAL_MS = 1700

function matchesFilter(investigation: DemoInvestigation, filter: InboxDemoFilter): boolean {
    switch (filter) {
        case 'attention':
            return !!investigation.unread || !!investigation.live || investigation.trend === 'up'
        case 'open':
            return investigation.status !== 'Resolved' && investigation.status !== 'Dismissed'
        case 'monitoring':
            return investigation.status === 'Verifying'
        case 'archived':
            return ['Resolved', 'Dismissed', 'Disputed'].includes(investigation.status)
        case 'all':
            return true
    }
}

