export interface sourceFilterCatalogLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentTeamId: number | null // teamLogic
    catalogStateFor: (sourceProduct: string, sourceType: string) => SourceFilterCatalogState
    filterCatalogs: SourceFilterCatalogApi[] | null
    filterCatalogsLoadFailed: boolean
    filterCatalogsLoading: boolean
    sourceFiltersEnabled: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sourceFilterCatalogLogicActions {
    loadFilterCatalogs: () => any
    loadFilterCatalogsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFilterCatalogsSuccess: (
        filterCatalogs: SourceFilterCatalogApi[] | null,
        payload?: any
    ) => {
        filterCatalogs: SourceFilterCatalogApi[] | null
        payload?: any
    }
}

