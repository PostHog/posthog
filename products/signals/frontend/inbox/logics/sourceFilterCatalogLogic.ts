import { signalsSourceConfigsFilterCatalogsRetrieve } from 'products/signals/frontend/generated/api'
import type { SourceFilterCatalogApi } from 'products/signals/frontend/generated/api.schemas'

/** What the roster knows about a source's filter catalog. */
export type SourceFilterCatalogState =
    | { status: 'unavailable' }
    | { status: 'loading' }
    | { status: 'failed' }
    | { status: 'ready'; catalog: SourceFilterCatalogApi }

