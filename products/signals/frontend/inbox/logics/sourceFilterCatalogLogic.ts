/**
 * The filter catalogs this project's organization may write to. The server lists only sources whose
 * filter it would accept on save, so a source missing from the list gets no filter editor.
 */
export const sourceFilterCatalogLogic: LogicWrapper<sourceFilterCatalogLogicType> = kea<sourceFilterCatalogLogicType>([
    path(['products', 'signals', 'inbox', 'logics', 'sourceFilterCatalogLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], featureFlagLogic, ['featureFlags']],
    })),
    loaders(({ values }) => ({
        filterCatalogs: [
            null as SourceFilterCatalogApi[] | null,
            {
                loadFilterCatalogs: async () => {
                    if (values.currentTeamId === null) {
                        return null
                    }
                    const response = await signalsSourceConfigsFilterCatalogsRetrieve(String(values.currentTeamId))
                    return response.results
                },
            },
        ],
    })),
    reducers({
        filterCatalogsLoadFailed: [
            false,
            {
                loadFilterCatalogs: () => false,
                loadFilterCatalogsSuccess: () => false,
                loadFilterCatalogsFailure: () => true,
            },
        ],
    }),
    selectors({
        sourceFiltersEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.SIGNALS_SOURCE_FILTERS],
        ],
        catalogStateFor: [
            (s) => [s.sourceFiltersEnabled, s.filterCatalogs, s.filterCatalogsLoadFailed],
            (
                sourceFiltersEnabled: boolean,
                filterCatalogs: SourceFilterCatalogApi[] | null,
                filterCatalogsLoadFailed: boolean
            ) =>
                (sourceProduct: string, sourceType: string): SourceFilterCatalogState => {
                    if (!sourceFiltersEnabled) {
                        return { status: 'unavailable' }
                    }
                    if (filterCatalogsLoadFailed) {
                        return { status: 'failed' }
                    }
                    if (filterCatalogs === null) {
                        return { status: 'loading' }
                    }
                    const catalog = filterCatalogs.find(
                        (entry) => entry.source_product === sourceProduct && entry.source_type === sourceType
                    )
                    return catalog ? { status: 'ready', catalog } : { status: 'unavailable' }
                },
        ],
    }),
    // Flags can resolve after mount, so load on the first time the flag reads as on.
    subscriptions(({ actions, values }) => ({
        sourceFiltersEnabled: (enabled: boolean) => {
            if (enabled && values.filterCatalogs === null && !values.filterCatalogsLoading) {
                actions.loadFilterCatalogs()
            }
        },
    })),
])
