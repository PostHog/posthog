/**
 * Multi-select + bulk dismiss / resolve for the inbox report list. Mirrors desktop
 * `inboxReportSelectionStore` (selection state) and `useInboxBulkActions`
 * (bulk suppress via `updateSignalReportState`). Kept deliberately thin: shift /
 * range selection lives in the list component; this logic owns the id set and
 * the state calls.
 */
export const inboxBulkActionsLogic = kea<inboxBulkActionsLogicType>([
    path(['scenes', 'inbox', 'logics', 'inboxBulkActionsLogic']),

    actions({
        toggleReportSelection: (reportId: string) => ({ reportId }),
        setSelectedReportIds: (reportIds: string[]) => ({ reportIds }),
        selectAll: (reportIds: string[]) => ({ reportIds }),
        clearSelection: true,
        /** Suppress every selected report with the chosen reason/note, then clear. */
        bulkDismiss: (dismissal: DismissalFeedback) => ({ dismissal }),
        bulkDismissSuccess: true,
        bulkDismissFailure: true,
        /** Resolve every selected report with the chosen reason/note, then clear. */
        bulkResolve: (reason: ResolveReasonValue, note: string) => ({ reason, note }),
        bulkResolveSuccess: true,
        bulkResolveFailure: true,
        /** Broadcast that a single report changed state elsewhere (dismissed, resolved, or refunded in
         * the detail pane), so every mounted list reconciles itself. Persisting the change is the
         * caller's responsibility. */
        reportStateChanged: true,
    }),

    reducers({
        selectedReportIds: [
            [] as string[],
            {
                toggleReportSelection: (state, { reportId }) =>
                    state.includes(reportId) ? state.filter((id) => id !== reportId) : [...state, reportId],
                setSelectedReportIds: (_, { reportIds }) => Array.from(new Set(reportIds)),
                selectAll: (_, { reportIds }) => Array.from(new Set(reportIds)),
                clearSelection: () => [],
            },
        ],
        isDismissing: [
            false,
            {
                bulkDismiss: () => true,
                bulkDismissSuccess: () => false,
                bulkDismissFailure: () => false,
            },
        ],
        isResolving: [
            false,
            {
                bulkResolve: () => true,
                bulkResolveSuccess: () => false,
                bulkResolveFailure: () => false,
            },
        ],
    }),

    selectors({
        selectedCount: [
            (s) => [s.selectedReportIds],
            (selectedReportIds: string[]): number => selectedReportIds.length,
        ],
        hasSelection: [
            (s) => [s.selectedReportIds],
            (selectedReportIds: string[]): boolean => selectedReportIds.length > 0,
        ],
    }),

    listeners(({ actions, values }) => ({
        bulkDismiss: async ({ dismissal }) => {
            const reportIds = values.selectedReportIds
            if (reportIds.length === 0) {
                actions.bulkDismissFailure()
                return
            }
            // Only the structured reason and repo correction — the free-form note can carry proprietary text.
            captureInboxReportAction({
                actionType: 'dismiss',
                surface: 'bulk_bar',
                isBulk: true,
                bulkSize: reportIds.length,
                extra: {
                    dismissal_reason: dismissal.reason,
                    ...(dismissal.correctedRepository
                        ? { dismissal_corrected_repository: dismissal.correctedRepository }
                        : {}),
                },
            })
            const results = await Promise.allSettled(
                reportIds.map((id) =>
                    api.signalReports.setState(id, {
                        state: 'suppressed',
                        ...suppressDismissalPayload(dismissal),
                    })
                )
            )
            const successCount = results.filter((r) => r.status === 'fulfilled').length
            const result: BulkActionResult = {
                successCount,
                failureCount: results.length - successCount,
            }

            actions.clearSelection()

            // Total failure: nothing was suppressed, so there's nothing for the list to drop.
            if (result.successCount === 0) {
                lemonToast.error(formatBulkSummary(result, 'dismissed'))
                actions.bulkDismissFailure()
                return
            }
            // Any success (partial or full) must reload so the suppressed reports leave the list.
            // A partial failure still surfaces as an error toast ("N dismissed, M failed").
            if (result.failureCount > 0) {
                lemonToast.error(formatBulkSummary(result, 'dismissed'))
            } else {
                lemonToast.success(formatBulkSummary(result, 'dismissed'))
            }
            actions.bulkDismissSuccess()
        },
        // Same shape as bulkDismiss. A report the backend refuses to resolve from its current status
        // (a 409) counts as failed, so the toast says how many were left in place.
        bulkResolve: async ({ reason, note }) => {
            const reportIds = values.selectedReportIds
            if (reportIds.length === 0) {
                actions.bulkResolveFailure()
                return
            }
            const trimmedNote = note.trim().slice(0, 4000)
            // Only the structured reason — the free-form note can carry proprietary text.
            captureInboxReportAction({
                actionType: 'resolve',
                surface: 'bulk_bar',
                isBulk: true,
                bulkSize: reportIds.length,
                extra: { dismissal_reason: reason },
            })
            const results = await Promise.allSettled(
                reportIds.map((id) =>
                    api.signalReports.setState(id, {
                        state: 'resolved',
                        dismissal_reason: reason,
                        ...(trimmedNote ? { dismissal_note: trimmedNote } : {}),
                    })
                )
            )
            const successCount = results.filter((r) => r.status === 'fulfilled').length
            const result: BulkActionResult = {
                successCount,
                failureCount: results.length - successCount,
            }

            actions.clearSelection()

            if (result.successCount === 0) {
                lemonToast.error(formatBulkSummary(result, 'resolved'))
                actions.bulkResolveFailure()
                return
            }
            if (result.failureCount > 0) {
                lemonToast.error(formatBulkSummary(result, 'resolved'))
            } else {
                lemonToast.success(formatBulkSummary(result, 'resolved'))
            }
            actions.bulkResolveSuccess()
        },
    })),
])
