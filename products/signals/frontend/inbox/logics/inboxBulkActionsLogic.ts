/** Tally of a bulk operation that ran one request per selected report. */
interface BulkActionResult {
    successCount: number
    failureCount: number
}

function formatBulkSummary(result: BulkActionResult, verb: 'dismissed' | 'resolved'): string {
    const { successCount, failureCount } = result
    const pluralized = successCount === 1 ? 'report' : 'reports'
    if (failureCount === 0) {
        return `${successCount} ${pluralized} ${verb}`
    }
    return `${successCount} ${pluralized} ${verb}, ${failureCount} failed`
}

function formatUnassignSummary({ successCount, failureCount }: BulkActionResult): string {
    if (successCount === 0) {
        return `Couldn't unassign you from ${pluralize(failureCount, 'report')}. Try again.`
    }
    const unassigned = `Unassigned you from ${pluralize(successCount, 'report')}`
    return failureCount === 0 ? unassigned : `${unassigned}, ${failureCount} failed`
}

function formatClaimSummary(claimedCount: number, refusedCount: number): string {
    const claimed = `Claimed ${pluralize(claimedCount, 'report')}`
    const refused =
        refusedCount === 1
            ? '1 report changed before it could be claimed'
            : `${refusedCount} reports changed before they could be claimed`
    if (refusedCount === 0) {
        return claimed
    }
    return claimedCount === 0 ? refused : `${claimed}. ${refused}`
}

