import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'

import { signalsTrialList } from 'products/signals/frontend/generated/api'
import type { SelfDrivingTrialStatusApi } from 'products/signals/frontend/generated/api.schemas'

import type { FeatureFlagsSet } from '../../../../../frontend/src/lib/logic/featureFlagLogic'

export interface SelfDrivingTrialLogicProps {
    teamId: number | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface selfDrivingTrialLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    error: string | null
    trial: SelfDrivingTrialStatusApi | null
    trialEnabled: boolean
    trialLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface selfDrivingTrialLogicActions {
    loadTrial: () => any
    loadTrialFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTrialSuccess: (
        trial: SelfDrivingTrialStatusApi | null,
        payload?: any
    ) => {
        trial: SelfDrivingTrialStatusApi | null
        payload?: any
    }
    syncPolling: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface selfDrivingTrialLogicMeta {
    key: number | 'unloaded'
    __keaTypeGenInternalSelectorTypes: {
        trialEnabled: (featureFlags: FeatureFlagsSet) => boolean
    }
}

export type selfDrivingTrialLogicType = MakeLogicType<
    selfDrivingTrialLogicValues,
    selfDrivingTrialLogicActions,
    SelfDrivingTrialLogicProps,
    selfDrivingTrialLogicMeta
>

export const selfDrivingTrialLogic = kea<selfDrivingTrialLogicType>([
    props({} as SelfDrivingTrialLogicProps),
    key(({ teamId }) => teamId ?? 'unloaded'),
    path((key) => ['products', 'signals', 'selfDrivingTrialLogic', key]),
    connect({ values: [featureFlagLogic, ['featureFlags']] }),
    actions({ syncPolling: true }),
    selectors({
        trialEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet) => !!featureFlags[FEATURE_FLAGS.SELF_DRIVING_UBP],
        ],
    }),
    loaders(({ props, values }) => ({
        trial: [
            null as SelfDrivingTrialStatusApi | null,
            {
                loadTrial: async (): Promise<SelfDrivingTrialStatusApi | null> =>
                    values.trialEnabled && props.teamId !== null ? signalsTrialList(String(props.teamId)) : null,
            },
        ],
    })),
    reducers({
        error: [
            null as string | null,
            {
                loadTrial: () => null,
                loadTrialFailure: () => 'Could not load Self-driving usage. Try again.',
            },
        ],
    }),
    listeners(({ actions, values, cache, props }) => ({
        syncPolling: () => {
            cache.disposables.dispose('trialPolling')
            if (!values.trialEnabled || props.teamId === null) {
                return
            }
            if (!values.trialLoading) {
                actions.loadTrial()
            }
            cache.disposables.add(() => {
                const timer = window.setInterval(() => {
                    if (!values.trialLoading) {
                        actions.loadTrial()
                    }
                }, 60_000)
                return () => window.clearInterval(timer)
            }, 'trialPolling')
        },
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => actions.syncPolling(),
    })),
    afterMount(({ actions }) => actions.syncPolling()),
])
