/**
 * The pre-computed "Suggested for this project" batch: read it, act on one pick, or pay for a new
 * scan. A scheduled headless run writes the batch ahead of time, so unlike the "Suggest a scout"
 * chat there is nothing to wait for here.
 *
 * The batch shrinks on its own — the read hides picks whose scout has since been turned on or
 * created — so every surface has to look right with one card, and `stale` is the steady state
 * rather than an error: any fleet change flips it, and the picks stay valid.
 */
export const scoutSuggestionsLogic = kea<scoutSuggestionsLogicType>([
    path(['products', 'signals', 'frontend', 'inbox', 'logics', 'scoutSuggestionsLogic']),
    connect(() => ({
        values: [
            scoutFleetLogic,
            ['scoutConfigs', 'aiConsentDisabledReason', 'runningChatType'],
            teamLogic,
            ['currentTeamId', 'currentProjectId'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [
            scoutFleetLogic,
            [
                'updateScoutConfig',
                'loadScoutConfigs',
                'startScoutChatTask',
                'startScoutChatTaskSuccess',
                'startScoutChatTaskFailure',
            ],
            featureFlagLogic,
            ['setFeatureFlags'],
        ],
    })),

    actions({
        dismissSuggestion: (item: ScoutSuggestionItemApi, surface: ScoutSuggestionSurface) => ({ item, surface }),
        createFromSuggestionReady: (item: ScoutSuggestionItemApi, existing: ExistingScoutForSuggestion | null) => ({
            item,
            existing,
        }),
        refineSuggestionWithAi: (item: ScoutSuggestionItemApi, surface: ScoutSuggestionSurface) => ({ item, surface }),
        restoreSuggestion: (suggestionId: string) => ({ suggestionId }),
        suggestionActionFinished: (suggestionId: string) => ({ suggestionId }),
        openCreateFromSuggestion: (item: ScoutSuggestionItemApi, surface: ScoutSuggestionSurface) => ({
            item,
            surface,
        }),
        closeCreateFromSuggestion: true,
        suggestionCreated: (item: ScoutSuggestionItemApi, surface: ScoutSuggestionSurface) => ({ item, surface }),
        requestRefresh: true,
        refreshRequestRefused: true,
        refreshFinished: true,
        startRefreshPolling: true,
        setCollapsed: (collapsed: boolean) => ({ collapsed }),
        hideStrip: true,
        showStrip: true,
        toggleSuggestionExpanded: (item: ScoutSuggestionItemApi, surface: ScoutSuggestionSurface) => ({
            item,
            surface,
        }),
        reportSuggestionsShown: (surface: ScoutSuggestionSurface) => ({ surface }),
    }),

    loaders(({ values }) => ({
        suggestionSet: [
            null as ScoutSuggestionSetApi | null,
            {
                loadSuggestions: async (_: void, breakpoint) => {
                    const teamId = values.currentTeamId
                    // Off the flag there is no surface to fill, so the project is never read.
                    if (!teamId || !values.suggestionsEnabled) {
                        return values.suggestionSet
                    }
                    const set = await signalsScoutSuggestionsList(String(teamId))
                    breakpoint()
                    return set
                },
            },
        ],
    })),

    // Built lazily so the persisted key reads the project the logic actually mounts in, not
    // whichever one was current when this module first loaded.
    reducers(() => ({
        // Optimistic removal. The next read excludes a dismissed pick server-side, so this only has
        // to cover the gap between the press and that read.
        hiddenSuggestionIds: [
            [] as string[],
            {
                dismissSuggestion: (state, { item }) => (state.includes(item.id) ? state : [...state, item.id]),
                // Custom only: a canonical pick disappears through the enabled-config filter
                // below instead, so a failed enable puts its card back rather than losing it.
                suggestionCreated: (state, { item }) =>
                    item.kind === 'canonical' || state.includes(item.id) ? state : [...state, item.id],
                restoreSuggestion: (state, { suggestionId }) => state.filter((id) => id !== suggestionId),
                // The server is the truth about what is still on offer, so an id it no longer
                // returns needs no local hiding and the list stays the length of one visit.
                loadSuggestionsSuccess: (state, { suggestionSet }) =>
                    state.filter((id) => (suggestionSet?.items ?? []).some((item) => item.id === id)),
            },
        ],
        busySuggestionIds: [
            [] as string[],
            {
                dismissSuggestion: (state, { item }) => [...state, item.id],
                // A canonical pick reads the existing scout before its form opens; a draft opens at once.
                openCreateFromSuggestion: (state, { item }) =>
                    item.kind === 'canonical' ? [...state, item.id] : state,
                refineSuggestionWithAi: (state, { item }) => [...state, item.id],
                suggestionActionFinished: (state, { suggestionId }) => state.filter((id) => id !== suggestionId),
            },
        ],
        // True from the press until the scan settles, so the button shows loading while the request
        // itself is still out, not only once the poll starts.
        isRefreshing: [
            false,
            {
                requestRefresh: () => true,
                refreshRequestRefused: () => false,
                startRefreshPolling: () => true,
                refreshFinished: () => false,
            },
        ],
        expandedSuggestionId: [
            null as string | null,
            {
                toggleSuggestionExpanded: (state, { item }) => (state === item.id ? null : item.id),
            },
        ],
        createFromSuggestion: [
            null as { item: ScoutSuggestionItemApi; existing: ExistingScoutForSuggestion | null } | null,
            {
                createFromSuggestionReady: (_, { item, existing }) => ({ item, existing }),
                closeCreateFromSuggestion: () => null,
                suggestionCreated: () => null,
            },
        ],
        // Null until someone touches the chevron, so the strip opens collapsed until they have an
        // opinion. Scoped to the user and project, so opening it here does not open it elsewhere.
        collapsedOverride: [
            null as boolean | null,
            buildUserScopedPersistenceConfig(),
            {
                setCollapsed: (_, { collapsed }) => collapsed,
                // Someone asking for the picks back wants to read them, not a collapsed line.
                showStrip: () => false,
            },
        ],
        // Closed outright with the cross. The "Suggest a scout" header button brings it back.
        stripHidden: [
            false,
            buildUserScopedPersistenceConfig(),
            {
                hideStrip: () => true,
                showStrip: () => false,
            },
        ],
    })),

    selectors({
        suggestions: [
            (s) => [s.suggestionSet, s.hiddenSuggestionIds, s.scoutConfigs],
            (
                suggestionSet: ScoutSuggestionSetApi | null,
                hiddenSuggestionIds: string[],
                scoutConfigs: SignalScoutConfig[] | null
            ): ScoutSuggestionItemApi[] => {
                // The same rule the read applies, but against the roster's own optimistically
                // patched configs: a scout that is on is no longer something to suggest.
                const enabled = new Set(
                    (scoutConfigs ?? []).filter((config) => config.enabled).map((config) => config.skill_name)
                )
                return (suggestionSet?.items ?? []).filter(
                    (item) => !hiddenSuggestionIds.includes(item.id) && !enabled.has(item.skill_name)
                )
            },
        ],
        batchStatus: [
            (s) => [s.suggestionSet],
            (suggestionSet: ScoutSuggestionSetApi | null): string => suggestionSet?.status ?? 'empty',
        ],
        batchAgeHours: [
            (s) => [s.suggestionSet],
            (suggestionSet: ScoutSuggestionSetApi | null): number | null =>
                suggestionSet?.generated_at
                    ? Math.max(0, Math.round(dayjs().diff(dayjs(suggestionSet.generated_at), 'hour', true) * 10) / 10)
                    : null,
        ],
        // The one gate every suggestions surface reads while the feature is dogfooded. The flag is
        // resolved per user, so two people on the same project can see different scouts tabs.
        suggestionsEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.SCOUTS_SUGGESTIONS_UI],
        ],
        // A project that has never been scanned has nothing to show and no refresh worth offering,
        // so the roster and the empty state stay exactly as they were.
        // A scan that found nothing still counts: it has a `generated_at`, and the person needs
        // the strip's "nothing left" line and its Refresh to ask again once data arrives. So does a
        // first scan that failed, which has no `generated_at` at all but still needs the Refresh.
        hasBatch: [
            (s) => [s.suggestionSet, s.suggestionsEnabled],
            (suggestionSet: ScoutSuggestionSetApi | null, suggestionsEnabled: boolean): boolean =>
                suggestionsEnabled &&
                suggestionSet !== null &&
                (suggestionSet.generated_at !== null ||
                    suggestionSet.items.length > 0 ||
                    suggestionSet.status === 'failed'),
        ],
        collapsed: [
            (s) => [s.collapsedOverride],
            (collapsedOverride: boolean | null): boolean => collapsedOverride ?? true,
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        dismissSuggestion: async ({ item, surface }) => {
            const teamId = values.currentTeamId
            if (!teamId) {
                actions.suggestionActionFinished(item.id)
                return
            }
            try {
                await signalsScoutSuggestionsDismiss(String(teamId), item.id)
                // Reported once the server holds it, so a failed dismissal is not counted as one.
                captureScoutSuggestionDismissed({
                    kind: suggestionKind(item),
                    skillName: item.skill_name,
                    surface,
                })
            } catch (error) {
                // A dismissal has no undo, so a failed one has to come back rather than quietly
                // disappear until the next read tells the person it was never hidden.
                actions.restoreSuggestion(item.id)
                lemonToast.error(
                    (error instanceof ApiError ? error.detail : null) ?? 'Could not dismiss that suggestion'
                )
            } finally {
                actions.suggestionActionFinished(item.id)
            }
        },
        refineSuggestionWithAi: async ({ item, surface }) => {
            captureScoutSuggestionClicked({
                kind: suggestionKind(item),
                skillName: item.skill_name,
                target: 'refine_with_ai',
                surface,
            })
            // The server builds the primed first turn from the stored draft, so the chat opens on
            // this suggestion instead of re-scanning the project from scratch. The card stays busy
            // until the task request settles, so a slow request cannot mint a second task.
            cache.refiningSuggestionId = item.id
            actions.startScoutChatTask('author_scout', 'scout authoring task', item.id)
        },
        startScoutChatTaskSuccess: () => {
            if (cache.refiningSuggestionId) {
                actions.suggestionActionFinished(cache.refiningSuggestionId)
                cache.refiningSuggestionId = null
            }
        },
        startScoutChatTaskFailure: () => {
            if (cache.refiningSuggestionId) {
                actions.suggestionActionFinished(cache.refiningSuggestionId)
                cache.refiningSuggestionId = null
            }
        },
        openCreateFromSuggestion: async ({ item, surface }) => {
            captureScoutSuggestionClicked({
                kind: suggestionKind(item),
                skillName: item.skill_name,
                target: item.kind === 'canonical' ? 'turn_on' : 'create',
                surface,
            })
            if (item.kind !== 'canonical') {
                actions.createFromSuggestionReady(item, null)
                return
            }
            // The form opens on the scout as it exists, so the person reads what it does before it
            // runs. Submitting then writes only its config, through the same update the roster uses.
            const config = values.scoutConfigs?.find((candidate) => candidate.skill_name === item.skill_name)
            const projectId = values.currentProjectId
            if (!config || typeof projectId !== 'number') {
                // The roster materializes the canonical fleet on open, so a missing row means the
                // sync has not landed yet rather than that the scout does not exist.
                lemonToast.error('This scout is still being set up on your project. Try again in a moment.')
                actions.loadScoutConfigs()
                actions.suggestionActionFinished(item.id)
                return
            }
            try {
                const skill = await llmSkillsNameRetrieve(String(projectId), item.skill_name)
                actions.createFromSuggestionReady(item, {
                    config,
                    description: skill.description,
                    body: skill.body,
                })
            } catch (error) {
                lemonToast.error(
                    (error instanceof ApiError ? error.detail : null) ??
                        'Could not load this scout. Try again in a moment.'
                )
            } finally {
                actions.suggestionActionFinished(item.id)
            }
        },
        suggestionCreated: ({ item, surface }) => {
            // Both one-click paths land here — turning a canonical scout on, and a custom draft
            // coming back from the create modal. A refinement chat only opens on the draft, so it
            // is a click, not a creation.
            captureScoutSuggestionCreated({
                kind: suggestionKind(item),
                skillName: item.skill_name,
                via: 'api',
                surface,
            })
            actions.loadSuggestions()
        },
        toggleSuggestionExpanded: ({ item, surface }) => {
            captureScoutSuggestionClicked({
                kind: suggestionKind(item),
                skillName: item.skill_name,
                // The reducer has already applied the toggle, so this reads the resulting state.
                target: values.expandedSuggestionId === item.id ? 'expand' : 'collapse',
                surface,
            })
        },
        reportSuggestionsShown: ({ surface }) => {
            captureScoutSuggestionsShown({
                count: values.suggestions.length,
                status: values.batchStatus,
                ageHours: values.batchAgeHours,
                collapsed: values.collapsed,
                surface,
            })
        },
        requestRefresh: async () => {
            const teamId = values.currentTeamId
            // The reducer already shows the button as busy; this non-reactive flag is what keeps a
            // second press, or a press during a running poll, from sending a second request.
            if (!teamId || cache.refreshInFlight || cache.refreshPolling) {
                return
            }
            cache.refreshInFlight = true
            try {
                await signalsScoutSuggestionsRefresh(String(teamId))
                captureScoutSuggestionsRefreshed({ outcome: 'accepted' })
                actions.startRefreshPolling()
            } catch (error) {
                const apiError = error instanceof ApiError ? error : null
                if (apiError?.status === 409) {
                    // A scan is already running, which is the state the skeletons describe anyway.
                    captureScoutSuggestionsRefreshed({ outcome: 'running' })
                    actions.startRefreshPolling()
                    return
                }
                captureScoutSuggestionsRefreshed({ outcome: apiError?.status === 429 ? 'capped' : 'failed' })
                actions.refreshRequestRefused()
                // The endpoint refuses for ordinary reasons — the daily cap, the org's AI setting,
                // a quota — so its own message is the one worth showing.
                lemonToast.error(apiError?.detail ?? 'Could not start a new scan')
            } finally {
                cache.refreshInFlight = false
            }
        },
        startRefreshPolling: () => {
            const generatedAtBefore = values.suggestionSet?.generated_at ?? null
            const statusBefore = values.suggestionSet?.status ?? null
            const startedAt = Date.now()
            cache.disposables.add(() => {
                const id = setInterval(() => {
                    if (Date.now() - startedAt >= REFRESH_POLL_TIMEOUT_MS) {
                        // One last read, so a scan that landed while the tab was hidden shows up
                        // now rather than on the next visit.
                        actions.refreshFinished()
                        actions.loadSuggestions()
                        return
                    }
                    actions.loadSuggestions()
                }, REFRESH_POLL_INTERVAL_MS)
                return () => clearInterval(id)
            }, 'suggestionsRefreshPoll')
            cache.refreshBaselineGeneratedAt = generatedAtBefore
            cache.refreshBaselineStatus = statusBefore
            cache.refreshPolling = true
        },
        loadSuggestionsSuccess: ({ suggestionSet }) => {
            if (!values.isRefreshing) {
                return
            }
            // A scan that produced nothing still lands as a `failed` row, so treat any conclusion as
            // the end of the wait rather than watching only for new items. A row that was already
            // `failed` before the refresh is the old failure, not the new scan settling.
            const settled =
                (suggestionSet?.generated_at ?? null) !== cache.refreshBaselineGeneratedAt ||
                (suggestionSet?.status === 'failed' && cache.refreshBaselineStatus !== 'failed')
            if (settled) {
                actions.refreshFinished()
            }
        },
        refreshFinished: () => {
            cache.refreshPolling = false
            cache.disposables.dispose('suggestionsRefreshPoll')
        },
        setFeatureFlags: () => {
            // Flags often resolve after the tab mounts, so the read is retried once the answer is
            // in. Without this a person on the flag opens the roster and sees no strip.
            if (values.suggestionsEnabled && values.suggestionSet === null && !values.suggestionSetLoading) {
                actions.loadSuggestions()
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadSuggestions()
    }),
])
