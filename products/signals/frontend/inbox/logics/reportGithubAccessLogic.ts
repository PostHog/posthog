export const reportGithubAccessLogic = kea<reportGithubAccessLogicType>([
    props({} as ReportGithubAccessLogicProps),
    key(({ report, surface }) => `${report?.id ?? 'none'}:${report?.repo_slug ?? ''}:${surface ?? 'detail_pane'}`),
    path((key) => ['products', 'signals', 'inbox', 'logics', 'reportGithubAccessLogic', key]),
    connect({
        values: [
            integrationsLogic,
            ['integrations', 'integrationsLoading', 'githubIntegrations', 'currentProjectId'],
            inboxSetupLogic,
            ['isGithubOptionalSetup', 'savedState', 'savedStateLoading'],
        ],
        actions: [
            integrationsLogic,
            ['loadIntegrations', 'loadIntegrationsSuccess', 'loadIntegrationsFailure'],
            inboxSetupLogic,
            ['loadSetup', 'loadSetupSuccess', 'loadSetupFailure'],
        ],
    }),
    actions({
        requireRepositorySelection: true,
        retryAccess: true,
        setConnectionOpen: (open: boolean) => ({ open }),
        setSelectedRepository: (repository: string) => ({ repository }),
        setSelectedIntegrationId: (integrationId: number) => ({ integrationId }),
    }),
    reducers({
        repositoryRequired: [
            false,
            {
                requireRepositorySelection: () => true,
            },
        ],
        selectedRepository: [
            '',
            {
                setSelectedRepository: (_, { repository }) => repository,
                setSelectedIntegrationId: () => '',
            },
        ],
        selectedIntegrationId: [
            null as number | null,
            { setSelectedIntegrationId: (_, { integrationId }) => integrationId },
        ],
        connectionOpen: [false, { setConnectionOpen: (_, { open }) => open }],
        accessFailed: [
            false,
            {
                checkAccessSuccess: () => false,
                checkAccessFailure: () => true,
                loadIntegrationsFailure: () => true,
            },
        ],
    }),
    loaders(({ values, props, cache }) => ({
        access: [
            null as 'available' | 'unavailable' | null,
            {
                checkAccess: async (_: void, breakpoint): Promise<'available' | 'unavailable' | null> => {
                    if (
                        !values.pilot ||
                        !props.report ||
                        values.integrations === null ||
                        values.currentProjectId === null
                    ) {
                        return null
                    }
                    const repository = (values.selectedRepository || props.report.repo_slug)?.toLowerCase()
                    const unavailable = Symbol('unavailable')
                    const probes = values.githubIntegrations
                        .filter((integration) => integration.installation_status !== 'unavailable')
                        .map((integration) =>
                            GithubAccessProbes.forContext().acquire(
                                String(values.currentProjectId),
                                integration.id,
                                repository
                            )
                        )
                    const release = (): void => probes.forEach((probe) => probe.release())
                    const disposables = cache.disposables
                    const disposableKey = `github-access-${(cache.probeSequence = (cache.probeSequence ?? 0) + 1)}`
                    disposables.add(() => release, disposableKey, { pauseOnPageHidden: false })
                    try {
                        await Promise.any(
                            probes.map(async (probe): Promise<void> => {
                                if (!(await probe.promise)) {
                                    throw unavailable
                                }
                            })
                        )
                        await breakpoint()
                        return 'available'
                    } catch (error) {
                        await breakpoint()
                        if (disposables.isDisposed) {
                            return null
                        }
                        if (!(error instanceof AggregateError)) {
                            throw error
                        }
                        const failure = error.errors.find((reason) => reason !== unavailable)
                        if (failure) {
                            throw failure
                        }
                        return 'unavailable'
                    } finally {
                        disposables.dispose(disposableKey)
                    }
                },
            },
        ],
    })),
    selectors({
        repositoryIntegrationId: [
            (s) => [s.selectedIntegrationId, s.githubIntegrations],
            (selected: number | null, integrations: IntegrationType[]): number | null =>
                selected ??
                integrations.find((integration) => integration.installation_status !== 'unavailable')?.id ??
                null,
        ],
        pilot: [(s) => [s.isGithubOptionalSetup], (available: boolean): boolean => available],
        loading: [
            (s) => [s.integrationsLoading, s.accessLoading, s.savedStateLoading],
            (integrationsLoading: boolean, accessLoading: boolean, setupLoading: boolean): boolean =>
                integrationsLoading || accessLoading || setupLoading,
        ],
        failed: [
            (s) => [s.pilot, s.accessFailed, s.integrations, s.loading],
            (pilot: boolean, failed: boolean, integrations: IntegrationType[] | null, loading: boolean): boolean =>
                pilot && (failed || (integrations === null && !loading)),
        ],
        // Outside the pilot, this checks only that a usable installation exists. Report tasks push with
        // the project's own GitHub integration, so without one the backend cannot open a pull request.
        githubMissing: [
            (s) => [s.pilot, s.integrations, s.githubIntegrations],
            (pilot: boolean, integrations: IntegrationType[] | null, githubIntegrations: IntegrationType[]): boolean =>
                !pilot &&
                integrations !== null &&
                !githubIntegrations.some((integration) => integration.installation_status !== 'unavailable'),
        ],
        repairNeeded: [
            (s) => [s.pilot, s.access, s.loading, s.failed, s.githubMissing],
            (
                pilot: boolean,
                access: 'available' | 'unavailable' | null,
                loading: boolean,
                failed: boolean,
                githubMissing: boolean
            ): boolean => githubMissing || (pilot && access === 'unavailable' && !loading && !failed),
        ],
        disabledReason: [
            (s) => [s.pilot, s.access, s.loading, s.failed, s.githubMissing],
            (
                pilot: boolean,
                access: 'available' | 'unavailable' | null,
                loading: boolean,
                failed: boolean,
                githubMissing: boolean
            ): string | null =>
                githubMissing
                    ? 'Connect or repair GitHub access to create a pull request'
                    : !pilot
                      ? null
                      : failed
                        ? "Couldn't check GitHub access. Try again."
                        : loading || access === null
                          ? 'Checking GitHub access'
                          : access === 'unavailable'
                            ? 'Connect or repair GitHub access to create a pull request'
                            : null,
        ],
    }),
    listeners(({ actions, values, props }) => {
        const track = (stage: string, outcome?: string): void => {
            if (!props.report) {
                return
            }
            captureInboxReportAction({
                report: props.report,
                actionType: 'github_access_recovery',
                surface: props.surface ?? 'detail_pane',
                extra: { stage, outcome },
            })
        }
        return {
            setSelectedRepository: ({ repository }) => {
                if (repository) {
                    track('repository_selected')
                }
                actions.checkAccess()
            },
            setSelectedIntegrationId: () => actions.checkAccess(),
            loadIntegrationsSuccess: () => {
                actions.checkAccess()
                if (!values.pilot && !values.githubMissing) {
                    actions.setConnectionOpen(false)
                }
            },
            loadSetupSuccess: () => actions.checkAccess(),
            loadSetupFailure: () => track('check', 'failed'),
            loadIntegrationsFailure: () => {
                if (values.pilot) {
                    track('check', 'failed')
                }
            },
            checkAccessFailure: () => track('check', 'failed'),
            checkAccessSuccess: ({ access }) => {
                if (access) {
                    track('check', access)
                }
                if (access === 'available') {
                    actions.setConnectionOpen(false)
                }
            },
            setConnectionOpen: ({ open }) => {
                if (open) {
                    track('connect')
                }
            },
            retryAccess: () => {
                if (values.loading) {
                    return
                }
                track('retry')
                GithubAccessProbes.forContext().invalidate(String(values.currentProjectId))
                if (values.savedState === null) {
                    actions.loadSetup()
                }
                actions.loadIntegrations()
            },
        }
    }),
    afterMount(({ actions }) => actions.checkAccess()),
])
