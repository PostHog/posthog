export const pullRequestsLogic = kea<pullRequestsLogicType>([
    path(['products', 'signals', 'inbox', 'pullRequestsLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        setPanelOpen: (open: boolean) => ({ open }),
        togglePanel: true,
        setFilter: (filter: PRMonitoringFilter) => ({ filter }),
        selectPR: (url: string | null) => ({ url }),
        setNote: (note: string) => ({ note }),
        refresh: true,
    }),
    reducers({
        panelOpen: [
            true,
            { persist: true },
            {
                setPanelOpen: (_, { open }) => open,
                togglePanel: (open) => !open,
            },
        ],
        filter: ['all' as PRMonitoringFilter, { setFilter: (_, { filter }) => filter }],
        selectedUrl: [null as string | null, { selectPR: (_, { url }) => url }],
        note: ['', { setNote: (_, { note }) => note, selectPR: () => '' }],
        listError: [false, { loadPullRequests: () => false, loadPullRequestsFailure: () => true }],
        overviewError: [false, { loadPullRequestOverview: () => false, loadPullRequestOverviewFailure: () => true }],
        monitorError: [
            null as string | null,
            {
                monitorPR: () => null,
                monitorPRFailure: (_, { error, errorObject }) =>
                    (typeof errorObject?.detail === 'string' && errorObject.detail) ||
                    error ||
                    'Could not start monitoring for this pull request.',
                selectPR: () => null,
            },
        ],
        page: [
            null as PRBrowserPageApi | null,
            {
                setFilter: () => null,
                monitorPRSuccess: (state, { monitoringRequest }) =>
                    state && monitoringRequest
                        ? {
                              ...state,
                              results: state.results.map((pr) =>
                                  pr.url === monitoringRequest.url
                                      ? {
                                            ...pr,
                                            report: {
                                                id: monitoringRequest.result.report_id,
                                                status: monitoringRequest.result.status,
                                            },
                                        }
                                      : pr
                              ),
                          }
                        : state,
            },
        ],
        overview: [
            null as PRBrowserOverviewApi | null,
            {
                selectPR: () => null,
                monitorPRSuccess: (state, { monitoringRequest }) =>
                    state && monitoringRequest?.url === state.pull_request.url
                        ? {
                              ...state,
                              pull_request: {
                                  ...state.pull_request,
                                  report: {
                                      id: monitoringRequest.result.report_id,
                                      status: monitoringRequest.result.status,
                                  },
                              },
                          }
                        : state,
            },
        ],
    }),
    loaders(({ values }) => ({
        page: [
            null as PRBrowserPageApi | null,
            {
                loadPullRequests: async (cursor: string | null, breakpoint) => {
                    const projectId = resolveProjectId(values.currentProjectId)
                    if (!projectId) {
                        return null
                    }
                    const page = await signalsPullRequestsList(projectId, {
                        monitoring: values.filter,
                        ...(cursor ? { cursor } : {}),
                    }).catch((error) => {
                        breakpoint()
                        throw error
                    })
                    breakpoint()
                    return {
                        ...page,
                        results: cursor
                            ? [...(values.page?.results ?? []), ...page.results].filter(
                                  (pr, index, all) => all.findIndex((other) => other.url === pr.url) === index
                              )
                            : page.results,
                    }
                },
            },
        ],
        overview: [
            null as PRBrowserOverviewApi | null,
            {
                loadPullRequestOverview: async (url: string | null, breakpoint) => {
                    const projectId = resolveProjectId(values.currentProjectId)
                    if (!url || !projectId) {
                        return null
                    }
                    const overview = await signalsPullRequestsOverviewRetrieve(projectId, {
                        pr_url: url,
                    }).catch((error) => {
                        breakpoint()
                        throw error
                    })
                    breakpoint()
                    return overview
                },
            },
        ],
        monitoringRequest: [
            null as { url: string; result: MonitorPRResponseApi } | null,
            {
                monitorPR: async (_: void, breakpoint) => {
                    const projectId = resolveProjectId(values.currentProjectId)
                    const url = values.selectedUrl
                    const existingReport = values.overview?.pull_request.report ?? values.selectedPR?.report
                    if (!projectId || !url || (existingReport && existingReport.status !== SignalReportStatus.FAILED)) {
                        return null
                    }
                    const hasNote = !!values.note.trim()
                    posthog.capture('Inbox PR action', {
                        inbox_client: INBOX_CLIENT,
                        action: 'monitor',
                        has_note: hasNote,
                    })
                    try {
                        const result = await signalsMonitorPrCreate(projectId, {
                            pr_url: url,
                            note: values.note.trim(),
                        })
                        breakpoint()
                        posthog.capture('Inbox PR action completed', {
                            inbox_client: INBOX_CLIENT,
                            action: 'monitor',
                            success: true,
                            report_id: result.report_id,
                            has_note: hasNote,
                        })
                        return { url, result }
                    } catch (error) {
                        breakpoint()
                        posthog.capture('Inbox PR action completed', {
                            inbox_client: INBOX_CLIENT,
                            action: 'monitor',
                            success: false,
                            has_note: hasNote,
                        })
                        throw error
                    }
                },
            },
        ],
    })),
    selectors({
        selectedPR: [
            (s) => [s.selectedUrl, s.overview, s.page],
            (
                url: string | null,
                overview: PRBrowserOverviewApi | null,
                page: PRBrowserPageApi | null
            ): PRBrowserItemApi | null =>
                overview?.pull_request.url === url
                    ? overview.pull_request
                    : (page?.results.find((pr) => pr.url === url) ?? null),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setPanelOpen: ({ open }) => {
            if (open && !cache.initialPageLoaded) {
                cache.initialPageLoaded = true
                actions.loadPullRequests(null)
            }
            capturePRAction(open ? 'open_panel' : 'close_panel')
        },
        togglePanel: () => {
            if (values.panelOpen && !cache.initialPageLoaded) {
                cache.initialPageLoaded = true
                actions.loadPullRequests(null)
            }
            capturePRAction(values.panelOpen ? 'open_panel' : 'close_panel')
        },
        setFilter: () => {
            cache.initialPageLoaded = true
            actions.loadPullRequests(null)
            posthog.capture('Inbox PR query changed', { inbox_client: INBOX_CLIENT, monitoring: values.filter })
        },
        selectPR: ({ url }) => {
            actions.loadPullRequestOverview(null)
            if (url) {
                actions.loadPullRequestOverview(url)
                posthog.capture('Inbox PR viewed', {
                    inbox_client: INBOX_CLIENT,
                    monitored: !!values.selectedPR?.report,
                })
            }
        },
        refresh: () => {
            cache.initialPageLoaded = true
            actions.loadPullRequests(null)
            if (values.selectedUrl) {
                actions.loadPullRequestOverview(values.selectedUrl)
            }
        },
        monitorPRSuccess: ({ monitoringRequest }) => {
            if (!monitoringRequest) {
                return
            }
            actions.loadPullRequests(null)
            if (values.selectedUrl === monitoringRequest.url) {
                actions.loadPullRequestOverview(values.selectedUrl)
            }
            monitoringTabLogic.findMounted()?.actions.loadReports()
        },
    })),
    actionToUrl(() => ({
        selectPR: ({ url }) => {
            if (!isOnMonitoringTab()) {
                return undefined
            }
            return [
                urls.inbox('monitoring'),
                { ...router.values.searchParams, pr: url || undefined },
                router.values.hashParams,
            ]
        },
        setFilter: ({ filter }) => {
            if (!isOnMonitoringTab()) {
                return undefined
            }
            return [
                urls.inbox('monitoring'),
                { ...router.values.searchParams, pr_filter: filter === 'all' ? undefined : filter },
                router.values.hashParams,
                { replace: true },
            ]
        },
        setPanelOpen: ({ open }) => {
            if (!isOnMonitoringTab() || open || !router.values.searchParams.pr) {
                return undefined
            }
            return [
                urls.inbox('monitoring'),
                { ...router.values.searchParams, pr: undefined },
                router.values.hashParams,
                { replace: true },
            ]
        },
        togglePanel: () => {
            if (!isOnMonitoringTab() || valuesOrFalse() || !router.values.searchParams.pr) {
                return undefined
            }
            return [
                urls.inbox('monitoring'),
                { ...router.values.searchParams, pr: undefined },
                router.values.hashParams,
                { replace: true },
            ]
        },
    })),
    urlToAction(({ actions, values, cache }) => ({
        [urls.inbox('monitoring')]: (_, search) => {
            const filter =
                search.pr_filter === 'monitored' || search.pr_filter === 'unmonitored' ? search.pr_filter : 'all'
            const url = typeof search.pr === 'string' ? search.pr : null
            if (filter !== values.filter) {
                actions.setFilter(filter)
            }
            if (url && !values.panelOpen) {
                actions.setPanelOpen(true)
            } else if ((values.panelOpen || !!url) && !cache.initialPageLoaded) {
                cache.initialPageLoaded = true
                actions.loadPullRequests(null)
            }
            if (url !== values.selectedUrl) {
                actions.selectPR(url)
            }
        },
    })),
    afterMount(({ actions, values, cache }) => {
        if (values.panelOpen && !cache.initialPageLoaded) {
            cache.initialPageLoaded = true
            actions.loadPullRequests(null)
        }
        cache.disposables.add(() => {
            const timer = setInterval(() => {
                if (
                    document.visibilityState === 'visible' &&
                    values.panelOpen &&
                    values.selectedUrl &&
                    !values.overviewLoading &&
                    isOnMonitoringTab()
                ) {
                    actions.loadPullRequestOverview(values.selectedUrl)
                }
            }, 30000)
            return () => clearInterval(timer)
        }, 'prRefresh')
    }),
])

function valuesOrFalse(): boolean {
    return pullRequestsLogic.findMounted()?.values.panelOpen ?? false
}
