import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { projectLogic } from 'scenes/projectLogic'
import { teamLogic } from 'scenes/teamLogic'

import { signalsMonitorPrCreate, signalsPullRequestsList } from 'products/signals/frontend/generated/api'
import type {
    MonitorPRResponseApi,
    PRBrowserItemApi,
    PRBrowserPageApi,
} from 'products/signals/frontend/generated/api.schemas'

import { INBOX_CLIENT } from '../inboxAnalytics'
import { monitoringTabLogic } from './monitoringTabLogic'

export const PR_MONITORING_NOTE_MAX_CHARS = 4000
export const PR_IN_PROGRESS_POLL_INTERVAL_MS = 5000

export type PRMonitoringFilter = 'all' | 'unmonitored' | 'monitored'
export type PRStateFilter = 'all' | 'open' | 'merged'

function hasInProgressPR(page: PRBrowserPageApi | null): boolean {
    return Boolean(page?.results.some((pr) => pr.report?.status === 'in_progress'))
}

// pinned: analytics event name and property keys — renaming breaks dashboards
export function capturePRAction(
    action: 'open_github' | 'open_report' | 'open_panel' | 'close_panel' | 'open_composer' | 'submit_monitor',
    extraProperties?: Record<string, boolean>
): void {
    posthog.capture('Inbox PR action', { inbox_client: INBOX_CLIENT, action, ...extraProperties })
}

function resolveProjectId(currentProjectId: number | null): string | null {
    const id = currentProjectId ?? teamLogic.values.currentTeamId
    return id != null ? String(id) : null
}

