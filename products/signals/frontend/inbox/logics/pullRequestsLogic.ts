export const pullRequestsLogic = kea<pullRequestsLogicType>([
    path(['products', 'signals', 'inbox', 'pullRequestsLogic']),
    actions({
        setFilter: (filter: PRMonitoringFilter) => ({ filter }),
        selectPR: (url: string | null) => ({ url }),
        setDetailTab: (tab: PRDetailTab) => ({ tab }),
        setNote: (note: string) => ({ note }),
        refresh: true,
        reportViewed: true,
    }),
    reducers({
        filter: ['all' as PRMonitoringFilter, { setFilter: (_, { filter }) => filter }],
        selectedUrl: [null as string | null, { selectPR: (_, { url }) => url }],
        detailTab: ['overview' as PRDetailTab, { setDetailTab: (_, { tab }) => tab, selectPR: () => 'overview' }],
        note: ['', { setNote: (_, { note }) => note, selectPR: () => '' }],
        listError: [false, { loadPage: () => false, loadPageFailure: () => true }],
        overviewError: [false, { loadOverview: () => false, loadOverviewFailure: () => true }],
        reportError: [false, { loadReport: () => false, loadReportFailure: () => true }],
        monitorError: [
            null as string | null,
            { monitorPR: () => null, monitorPRFailure: (_, { error }) => error, selectPR: () => null },
        ],
        page: [null as PRBrowserPageApi | null, { setFilter: () => null }],
        overview: [
            null as PRBrowserOverviewApi | null,
            {
                selectPR: () => null,
                monitorPRSuccess: (state, { monitoringRequest }) =>
                    state && monitoringRequest?.url === state.pull_request.url
                        ? {
                              ...state,
                              pull_request: {
                                  ...state.pull_request,
                                  report: {
                                      id: monitoringRequest.result.report_id,
                                      status: monitoringRequest.result.status,
                                  },
                              },
                          }
                        : state,
            },
        ],
        report: [null as SignalReport | null, { selectPR: () => null }],
    }),
    loaders(({ values }) => ({
        page: [
            null as PRBrowserPageApi | null,
            {
                loadPage: async (cursor: string | null, breakpoint) => {
                    const page = await signalsPullRequestsList(String(teamLogic.values.currentTeamId), {
                        monitoring: values.filter,
                        ...(cursor ? { cursor } : {}),
                    }).catch((error) => {
                        breakpoint()
                        throw error
                    })
                    breakpoint()
                    return {
                        ...page,
                        results: cursor
                            ? [...(values.page?.results ?? []), ...page.results].filter(
                                  (pr, index, all) => all.findIndex((other) => other.url === pr.url) === index
                              )
                            : page.results,
                    }
                },
            },
        ],
        overview: [
            null as PRBrowserOverviewApi | null,
            {
                loadOverview: async (url: string | null, breakpoint) => {
                    if (!url) {
                        return null
                    }
                    const overview = await signalsPullRequestsOverviewRetrieve(String(teamLogic.values.currentTeamId), {
                        pr_url: url,
                    }).catch((error) => {
                        breakpoint()
                        throw error
                    })
                    breakpoint()
                    return overview
                },
            },
        ],
        report: [
            null as SignalReport | null,
            {
                loadReport: async (id: string | null, breakpoint): Promise<SignalReport | null> => {
                    if (!id) {
                        return null
                    }
                    const report = await signalsReportsRetrieve(String(teamLogic.values.currentTeamId), id).catch(
                        (error) => {
                            breakpoint()
                            throw error
                        }
                    )
                    breakpoint()
                    return {
                        ...report,
                        status: report.status as SignalReportStatus,
                        priority: report.priority as SignalReport['priority'],
                        actionability: report.actionability as SignalReport['actionability'],
                        charts: [...report.charts],
                        metrics: [...report.metrics],
                        source_products: [...report.source_products],
                        suggested_prompts: [...report.suggested_prompts],
                    }
                },
            },
        ],
        monitoringRequest: [
            null as { url: string; result: MonitorPRResponseApi } | null,
            {
                monitorPR: async (_: void, breakpoint) => {
                    const url = values.selectedUrl
                    if (!url || values.overview?.pull_request.report) {
                        return null
                    }
                    const hasNote = !!values.note.trim()
                    posthog.capture('Inbox PR action', {
                        inbox_client: INBOX_CLIENT,
                        action: 'monitor',
                        has_note: hasNote,
                    })
                    try {
                        const result = await signalsMonitorPrCreate(String(teamLogic.values.currentTeamId), {
                            pr_url: url,
                            note: values.note.trim(),
                        })
                        breakpoint()
                        posthog.capture('Inbox PR action completed', {
                            inbox_client: INBOX_CLIENT,
                            action: 'monitor',
                            success: true,
                            report_id: result.report_id,
                            has_note: hasNote,
                        })
                        return { url, result }
                    } catch (error) {
                        breakpoint()
                        posthog.capture('Inbox PR action completed', {
                            inbox_client: INBOX_CLIENT,
                            action: 'monitor',
                            success: false,
                            has_note: hasNote,
                        })
                        throw error
                    }
                },
            },
        ],
    })),
    selectors({
        selectedPR: [
            (s) => [s.selectedUrl, s.overview, s.page],
            (
                url: string | null,
                overview: PRBrowserOverviewApi | null,
                page: PRBrowserPageApi | null
            ): PRBrowserItemApi | null =>
                overview?.pull_request.url === url
                    ? overview.pull_request
                    : (page?.results.find((pr) => pr.url === url) ?? null),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setFilter: () => {
            actions.loadPage(null)
            posthog.capture('Inbox PR query changed', { inbox_client: INBOX_CLIENT, monitoring: values.filter })
        },
        selectPR: ({ url }) => {
            actions.loadOverview(null)
            actions.loadReport(null)
            if (url) {
                actions.loadOverview(url)
            }
            cache.openedReportId = null
            cache.disposables.dispose('reportRead')
            posthog.capture('Inbox PR viewed', { inbox_client: INBOX_CLIENT, tab: 'overview' })
        },
        refresh: () => {
            actions.loadPage(null)
            actions.loadOverview(values.selectedUrl)
        },
        loadOverviewSuccess: ({ overview }) => {
            actions.loadReport(overview?.pull_request.report?.id ?? null)
        },
        setDetailTab: () => {
            if (values.detailTab !== 'report') {
                cache.disposables.dispose('reportRead')
                cache.openedReportId = null
            }
            actions.reportViewed()
            posthog.capture('Inbox PR viewed', {
                inbox_client: INBOX_CLIENT,
                tab: values.detailTab,
                monitored: !!values.selectedPR?.report,
            })
        },
        loadReportSuccess: () => actions.reportViewed(),
        reportViewed: () => {
            if (values.detailTab !== 'report' || !values.report || cache.openedReportId === values.report.id) {
                return
            }
            cache.openedReportId = values.report.id
            const openedAt = Date.now()
            const report = values.report
            cache.disposables.add(() => {
                let activeTimeMs = 0
                const timer = setInterval(() => {
                    if (document.visibilityState === 'visible' && document.hasFocus()) {
                        activeTimeMs += 1000
                    }
                    if (activeTimeMs >= 8000) {
                        captureInboxReportRead({
                            report,
                            rank: null,
                            listSize: null,
                            activeTimeMs,
                            timeSinceOpenMs: Date.now() - openedAt,
                        })
                        cache.disposables.dispose('reportRead')
                    }
                }, 1000)
                return () => clearInterval(timer)
            }, 'reportRead')
            captureInboxReportOpened({
                report: values.report,
                openMethod: 'click',
                linkSource: null,
                previousReportId: null,
                rank: null,
                listSize: null,
                section: null,
                rankerId: null,
                personalTier: null,
                personalReasonShown: false,
            })
        },
        monitorPRSuccess: ({ monitoringRequest }) => {
            if (!monitoringRequest) {
                return
            }
            actions.loadPage(null)
            if (values.selectedUrl === monitoringRequest.url) {
                actions.loadOverview(values.selectedUrl)
                actions.loadReport(monitoringRequest.result.report_id)
                actions.setDetailTab('report')
            }
        },
    })),
    actionToUrl(() => ({
        selectPR: ({ url }) => [
            urls.inbox('prs'),
            { ...router.values.searchParams, pr: url || undefined, pr_tab: undefined },
            router.values.hashParams,
        ],
        setDetailTab: ({ tab }) => [
            urls.inbox('prs'),
            { ...router.values.searchParams, pr_tab: tab === 'report' ? tab : undefined },
            router.values.hashParams,
        ],
        setFilter: ({ filter }) => [
            urls.inbox('prs'),
            { ...router.values.searchParams, monitoring: filter === 'all' ? undefined : filter },
            router.values.hashParams,
            { replace: true },
        ],
    })),
    urlToAction(({ actions, values }) => ({
        [urls.inbox('prs')]: (_, search) => {
            const filter =
                search.monitoring === 'monitored' || search.monitoring === 'unmonitored' ? search.monitoring : 'all'
            const url = typeof search.pr === 'string' ? search.pr : null
            const tab = search.pr_tab === 'report' ? 'report' : 'overview'
            if (filter !== values.filter) {
                actions.setFilter(filter)
            }
            if (url !== values.selectedUrl) {
                actions.selectPR(url)
            }
            if (tab !== values.detailTab) {
                actions.setDetailTab(tab)
            }
        },
    })),
    afterMount(({ actions, values, cache }) => {
        actions.loadPage(null)
        cache.disposables.add(() => {
            const timer = setInterval(() => {
                if (
                    document.visibilityState === 'visible' &&
                    values.detailTab === 'report' &&
                    values.report &&
                    !values.reportLoading
                ) {
                    actions.loadReport(values.report.id)
                }
            }, 10000)
            return () => clearInterval(timer)
        }, 'reportRefresh')
        cache.disposables.add(() => {
            const timer = setInterval(() => {
                if (document.visibilityState === 'visible' && values.selectedUrl && !values.overviewLoading) {
                    actions.loadOverview(values.selectedUrl)
                }
            }, 30000)
            return () => clearInterval(timer)
        }, 'prRefresh')
    }),
])
