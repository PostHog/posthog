export type PRMonitoringFilter = NonNullable<SignalsPullRequestsListParams['monitoring']>

export function capturePRAction(
    action: 'open_github' | 'open_ci_check' | 'open_report' | 'open_panel' | 'close_panel'
): void {
    posthog.capture('Inbox PR action', { inbox_client: INBOX_CLIENT, action })
}

function resolveProjectId(currentProjectId: number | null): string | null {
    const id = currentProjectId ?? teamLogic.values.currentTeamId
    return id != null ? String(id) : null
}

function isOnMonitoringTab(): boolean {
    return router.values.location.pathname === urls.inbox('monitoring')
}

