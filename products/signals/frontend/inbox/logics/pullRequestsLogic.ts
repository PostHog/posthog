export const pullRequestsLogic = kea<pullRequestsLogicType>([
    path(['products', 'signals', 'inbox', 'pullRequestsLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        setPanelOpen: (open: boolean) => ({ open }),
        setFilter: (filter: PRMonitoringFilter) => ({ filter }),
        setStateFilter: (stateFilter: PRStateFilter) => ({ stateFilter }),
        openComposer: (url: string) => ({ url }),
        closeComposer: () => true,
        setDraftNote: (url: string, note: string) => ({ url, note }),
        monitorPR: (url: string, note?: string) => ({ url, note }),
        monitorPRDone: (url: string, result: MonitorPRResponseApi | null) => ({ url, result }),
    }),
    loaders(({ values }) => ({
        page: [
            null as PRBrowserPageApi | null,
            {
                loadPullRequests: async (_: void, breakpoint) => {
                    await breakpoint(10)
                    const projectId = resolveProjectId(values.currentProjectId)
                    if (!projectId) {
                        return null
                    }
                    try {
                        const page = await signalsPullRequestsList(projectId)
                        breakpoint()
                        return page
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        panelOpen: [true, { persist: true }, { setPanelOpen: (_, { open }) => open }],
        filter: ['all' as PRMonitoringFilter, { setFilter: (_, { filter }) => filter }],
        stateFilter: ['all' as PRStateFilter, { setStateFilter: (_, { stateFilter }) => stateFilter }],
        page: [
            null as PRBrowserPageApi | null,
            {
                monitorPRDone: (state, { url, result }) =>
                    state && result
                        ? {
                              ...state,
                              results: state.results.map((pr) =>
                                  pr.url === url
                                      ? { ...pr, report: { id: result.report_id, status: result.status } }
                                      : pr
                              ),
                          }
                        : state,
            },
        ],
        listError: [
            false,
            {
                loadPullRequests: () => false,
                loadPullRequestsFailure: () => true,
            },
        ],
        composingUrl: [
            null as string | null,
            {
                openComposer: (_, { url }) => url,
                closeComposer: () => null,
                setPanelOpen: (state, { open }) => (open ? state : null),
                monitorPRDone: (state, { url, result }) => (result && state === url ? null : state),
            },
        ],
        draftNotes: [
            {} as Record<string, string>,
            {
                setDraftNote: (state, { url, note }) => ({ ...state, [url]: note }),
                monitorPRDone: (state, { url, result }) => {
                    if (!result) {
                        return state
                    }
                    const { [url]: _, ...rest } = state
                    return rest
                },
            },
        ],
        monitoringUrls: [
            {} as Record<string, boolean>,
            {
                monitorPR: (state, { url }) => (state[url] ? state : { ...state, [url]: true }),
                monitorPRDone: (state, { url }) => {
                    const { [url]: _, ...rest } = state
                    return rest
                },
            },
        ],
    }),
    selectors({
        filteredPRs: [
            (s) => [s.page, s.filter, s.stateFilter],
            (
                page: PRBrowserPageApi | null,
                filter: PRMonitoringFilter,
                stateFilter: PRStateFilter
            ): PRBrowserItemApi[] =>
                (page?.results ?? []).filter((pr: PRBrowserItemApi) => {
                    if (filter !== 'all' && (filter === 'monitored') !== Boolean(pr.report)) {
                        return false
                    }
                    return stateFilter === 'all' || pr.state === stateFilter
                }),
        ],
    }),
    listeners(({ actions, cache, values }) => ({
        openComposer: () => {
            capturePRAction('open_composer')
        },
        monitorPR: async ({ url, note }) => {
            cache.inFlightUrls ??= new Set<string>()
            if (cache.inFlightUrls.has(url)) {
                return
            }
            const projectId = resolveProjectId(values.currentProjectId)
            if (!projectId) {
                actions.monitorPRDone(url, null)
                return
            }
            cache.inFlightUrls.add(url)
            const initialReportId = currentOpenReportId()
            const trimmedNote = (note ?? values.draftNotes[url] ?? '').trim()
            capturePRAction('submit_monitor', { has_note: Boolean(trimmedNote) })
            try {
                const result = await signalsMonitorPrCreate(
                    projectId,
                    trimmedNote ? { pr_url: url, note: trimmedNote } : { pr_url: url }
                )
                actions.monitorPRDone(url, result)
                monitoringTabLogic.findMounted()?.actions.loadReports()
                syncOpenReportAfterMonitor(initialReportId, result.report_id)
            } catch (err: any) {
                lemonToast.error(
                    err?.data?.detail || err?.detail || 'Could not start monitoring for this pull request.'
                )
                actions.monitorPRDone(url, null)
            } finally {
                cache.inFlightUrls.delete(url)
            }
        },
        setPanelOpen: ({ open }) => {
            capturePRAction(open ? 'open_panel' : 'close_panel')
            if (open && !values.page && !values.pageLoading) {
                actions.loadPullRequests()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.panelOpen) {
            actions.loadPullRequests()
        }
    }),
])
