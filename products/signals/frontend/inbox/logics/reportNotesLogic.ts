/** Who a note reaches, in the words the notes list and the target picker use. */
export function reportNoteAudience(skillName: string, scoutNamesBySkill: Record<string, string>): string {
    return skillName === EVERY_SCOUT
        ? 'For every scout'
        : `For ${scoutNamesBySkill[skillName] ?? prettifyScoutSkillName(skillName)}`
}

/**
 * The scout notes about one report: the ones people left from it, plus the ones the inbox forwarded
 * when it was dismissed, discussed, or rated. Notes have no report column, so both kinds are found by
 * the report id they quote (see `buildReportNoteContent`).
 */
export const reportNotesLogic = kea<reportNotesLogicType>([
    path((key) => ['products', 'signals', 'inbox', 'logics', 'reportNotesLogic', key]),
    props({} as ReportNotesLogicProps),
    key((props) => props.reportId),

    actions({
        createNote: (content: string, skillName: string) => ({ content, skillName }),
        createNoteFailed: true,
        createNoteFinished: true,
        deleteNote: (noteId: string) => ({ noteId }),
        deleteNoteFailed: (noteId: string) => ({ noteId }),
    }),

    loaders(({ props }) => ({
        notes: [
            [] as ScoutNoteApi[],
            {
                loadNotes: async (_payload: void, breakpoint) => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        return []
                    }
                    // A save reloads the notes, so the breakpoint on both paths stops an older read
                    // answering for a newer one.
                    const notes = await withPanelLoadTimeout('report_notes', (options) =>
                        signalsScoutNotesList(
                            String(teamId),
                            { text: props.reportId, limit: NOTES_FETCH_LIMIT },
                            options
                        )
                    ).catch((error: unknown) => {
                        breakpoint()
                        throw error
                    })
                    breakpoint()
                    return notes
                },
            },
        ],
        scoutConfigs: [
            null as SignalScoutConfigApi[] | null,
            {
                loadScoutConfigs: async () => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        return null
                    }
                    return await signalsScoutConfigList(String(teamId))
                },
            },
        ],
    })),

    reducers({
        // Retired here, whatever the server has said since. A load that was already in flight when
        // the note was retired can resolve after the delete and would otherwise resurrect the row.
        retiredNoteIds: [
            [] as string[],
            {
                deleteNote: (state, { noteId }) => [...state, noteId],
                deleteNoteFailed: (state, { noteId }) => state.filter((id) => id !== noteId),
            },
        ],
        notesLoadFailed: [
            false,
            {
                loadNotes: () => false,
                loadNotesSuccess: () => false,
                loadNotesFailure: () => true,
            },
        ],
        savingNote: [
            false,
            {
                createNote: () => true,
                createNoteFinished: () => false,
            },
        ],
        // The dialog awaits `createNote` and reads this to decide whether to close, since a listener
        // cannot return a result.
        lastSaveFailed: [
            false,
            {
                createNote: () => false,
                createNoteFailed: () => true,
            },
        ],
    }),

    selectors({
        activeNotes: [
            (s) => [s.notes, s.retiredNoteIds],
            (notes: ScoutNoteApi[], retiredNoteIds: string[]): ScoutNoteApi[] =>
                retiredNoteIds.length ? notes.filter((note) => !retiredNoteIds.includes(note.id)) : notes,
        ],
        scoutNamesBySkill: [
            (s) => [s.scoutConfigs],
            (scoutConfigs: SignalScoutConfigApi[] | null): Record<string, string> =>
                Object.fromEntries((scoutConfigs ?? []).map((config) => [config.skill_name, scoutDisplayName(config)])),
        ],
        // The report's own scout first, since that is who a note on its report is usually for. Without
        // one, every scout leads. The rest of the fleet follows by name.
        noteTargetOptions: [
            (s) => [s.scoutNamesBySkill, (_, props) => props.reportScoutName],
            (scoutNamesBySkill: Record<string, string>, reportScoutName: string | null): ReportNoteTargetOption[] => {
                const everyScout = { value: EVERY_SCOUT, label: 'Every scout' }
                const others = Object.entries(scoutNamesBySkill)
                    .filter(([skillName]) => skillName !== reportScoutName)
                    .map(([skillName, name]) => ({ value: skillName, label: name }))
                    .sort((a, b) => a.label.localeCompare(b.label))
                if (!reportScoutName) {
                    return [everyScout, ...others]
                }
                const reportScoutLabel = scoutNamesBySkill[reportScoutName] ?? prettifyScoutSkillName(reportScoutName)
                return [
                    { value: reportScoutName, label: `${reportScoutLabel} (filed this report)` },
                    everyScout,
                    ...others,
                ]
            },
        ],
    }),

    listeners(({ actions, props, values }) => ({
        createNote: async ({ content, skillName }) => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                actions.createNoteFailed()
                actions.createNoteFinished()
                return
            }
            try {
                await signalsScoutNotesCreate(String(teamId), {
                    content: buildReportNoteContent(props.reportId, content),
                    ...(skillName !== EVERY_SCOUT ? { skill_name: skillName } : {}),
                })
                captureScoutAction({
                    actionType: 'leave_note',
                    surface: 'report_detail',
                    skillName: skillName || null,
                    extra: {
                        report_id: props.reportId,
                        report_has_scout: !!props.reportScoutName,
                        note_target:
                            skillName === EVERY_SCOUT
                                ? 'fleet'
                                : skillName === props.reportScoutName
                                  ? 'report_scout'
                                  : 'other_scout',
                    },
                })
                lemonToast.success(
                    skillName === EVERY_SCOUT
                        ? 'Every scout picks this up on its next run'
                        : 'The scout picks this up on its next run'
                )
                actions.loadNotes()
            } catch (error: any) {
                lemonToast.error(error?.detail || error?.message || 'Failed to leave the note')
                actions.createNoteFailed()
            } finally {
                actions.createNoteFinished()
            }
        },
        deleteNote: async ({ noteId }) => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                return
            }
            const skillName = values.notes.find((note) => note.id === noteId)?.skill_name
            // Optimistic: `retiredNoteIds` hides the row at once; a failed delete un-hides it.
            try {
                await signalsScoutNotesDestroy(String(teamId), noteId)
                captureScoutAction({
                    actionType: 'delete_note',
                    surface: 'report_detail',
                    skillName: skillName || null,
                    extra: { report_id: props.reportId },
                })
            } catch (error: any) {
                lemonToast.error(error?.detail || error?.message || 'Failed to retire the note')
                actions.deleteNoteFailed(noteId)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadNotes()
        actions.loadScoutConfigs()
    }),
])
