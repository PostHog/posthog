/** Who a scout note reaches, in the words the Activity entry and the target picker use. */
export function reportNoteAudience(skillName: string, scoutNamesBySkill: Record<string, string>): string {
    return skillName === EVERY_SCOUT
        ? 'For every scout'
        : `For ${scoutNamesBySkill[skillName] ?? prettifyScoutSkillName(skillName)}`
}

/**
 * The report's own scout first, since that is who a note on its report is usually for. Without one,
 * every scout leads. The rest of the fleet follows by name.
 */
export function reportNoteTargetOptions(
    scoutNamesBySkill: Record<string, string>,
    reportScoutName: string | null
): ReportNoteTargetOption[] {
    const everyScout = { value: EVERY_SCOUT, label: 'Every scout' }
    const others = Object.entries(scoutNamesBySkill)
        .filter(([skillName]) => skillName !== reportScoutName)
        .map(([skillName, name]) => ({ value: skillName, label: name }))
        .sort((a, b) => a.label.localeCompare(b.label))
    if (!reportScoutName) {
        return [everyScout, ...others]
    }
    const reportScoutLabel = scoutNamesBySkill[reportScoutName] ?? prettifyScoutSkillName(reportScoutName)
    return [{ value: reportScoutName, label: `${reportScoutLabel} (filed this report)` }, everyScout, ...others]
}

/**
 * Notes people add to a report. Every note lands on the report's activity log: a plain `note` entry,
 * or, when it is sent to the scouts, a scout note that the server records as a `scout_note_left` entry.
 * The scout notes that quote the report id are loaded so each such entry can say whether the scouts
 * still read it.
 */
export const reportNotesLogic = kea<reportNotesLogicType>([
    path((key) => ['products', 'signals', 'inbox', 'logics', 'reportNotesLogic', key]),
    props({} as ReportNotesLogicProps),
    key((props) => props.reportId),

    actions({
        // `scoutTarget` is null for a note that stays on the report, else a skill name or `EVERY_SCOUT`.
        addNote: (content: string, scoutTarget: string | null, reportScoutName: string | null) => ({
            content,
            scoutTarget,
            reportScoutName,
        }),
        addNoteFailed: true,
        addNoteFinished: true,
        retireNote: (noteId: string) => ({ noteId }),
        retireNoteFailed: (noteId: string) => ({ noteId }),
    }),

    loaders(({ props }) => ({
        notes: [
            [] as ScoutNoteApi[],
            {
                loadNotes: async (_payload: void, breakpoint) => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        return []
                    }
                    // A save reloads the notes, so the breakpoint on both paths stops an older read
                    // answering for a newer one.
                    const notes = await withPanelLoadTimeout('report_notes', (options) =>
                        signalsScoutNotesList(
                            String(teamId),
                            { text: props.reportId, limit: NOTES_FETCH_LIMIT },
                            options
                        )
                    ).catch((error: unknown) => {
                        breakpoint()
                        throw error
                    })
                    breakpoint()
                    return notes
                },
            },
        ],
        scoutConfigs: [
            null as SignalScoutConfigApi[] | null,
            {
                loadScoutConfigs: async () => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        return null
                    }
                    return await signalsScoutConfigList(String(teamId))
                },
            },
        ],
    })),

    reducers({
        // Retired here, whatever the server has said since. A load that was already in flight when
        // the note was retired can resolve after the delete and would otherwise mark it active again.
        retiredNoteIds: [
            [] as string[],
            {
                retireNote: (state, { noteId }) => [...state, noteId],
                retireNoteFailed: (state, { noteId }) => state.filter((id) => id !== noteId),
            },
        ],
        notesLoadFailed: [
            false,
            {
                loadNotes: () => false,
                loadNotesSuccess: () => false,
                loadNotesFailure: () => true,
            },
        ],
        // Until the first read lands, a scout note's status is unknown rather than inactive.
        notesResolved: [
            false,
            {
                loadNotesSuccess: () => true,
            },
        ],
        savingNote: [
            false,
            {
                addNote: () => true,
                addNoteFinished: () => false,
            },
        ],
        // The dialog awaits `addNote` and reads this to decide whether to close, since a listener
        // cannot return a result.
        lastSaveFailed: [
            false,
            {
                addNote: () => false,
                addNoteFailed: () => true,
            },
        ],
    }),

    selectors({
        activeNoteIds: [
            (s) => [s.notes, s.retiredNoteIds],
            (notes: ScoutNoteApi[], retiredNoteIds: string[]): Set<string> =>
                new Set(notes.map((note) => note.id).filter((id) => !retiredNoteIds.includes(id))),
        ],
        scoutNamesBySkill: [
            (s) => [s.scoutConfigs],
            (scoutConfigs: SignalScoutConfigApi[] | null): Record<string, string> =>
                Object.fromEntries((scoutConfigs ?? []).map((config) => [config.skill_name, scoutDisplayName(config)])),
        ],
    }),

    listeners(({ actions, props, values }) => ({
        addNote: async ({ content, scoutTarget, reportScoutName }) => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                actions.addNoteFailed()
                actions.addNoteFinished()
                return
            }
            const detailLogic = inboxReportDetailLogic.findMounted({ reportId: props.reportId })
            try {
                if (scoutTarget === null) {
                    await signalsReportArtefactsCreate(String(teamId), props.reportId, {
                        artefact_type: 'note',
                        content: { note: content },
                    })
                } else {
                    await signalsScoutNotesCreate(String(teamId), {
                        content,
                        report_id: props.reportId,
                        ...(scoutTarget !== EVERY_SCOUT ? { skill_name: scoutTarget } : {}),
                    })
                }
                const noteTarget =
                    scoutTarget === null
                        ? 'report'
                        : scoutTarget === EVERY_SCOUT
                          ? 'fleet'
                          : scoutTarget === reportScoutName
                            ? 'report_scout'
                            : 'other_scout'
                captureInboxReportAction({
                    report: detailLogic?.props.report,
                    actionType: 'add_note',
                    surface: 'detail_pane',
                    extra: { sent_to_scouts: scoutTarget !== null, note_target: noteTarget },
                })
                if (scoutTarget !== null) {
                    // Scout surfaces count notes left from every surface through this event.
                    captureScoutAction({
                        actionType: 'leave_note',
                        surface: 'report_detail',
                        skillName: scoutTarget || null,
                        extra: {
                            report_id: props.reportId,
                            report_has_scout: !!reportScoutName,
                            note_target: noteTarget,
                        },
                    })
                    lemonToast.success(
                        scoutTarget === EVERY_SCOUT
                            ? 'Note added. Every scout picks it up on its next run.'
                            : 'Note added. The scout picks it up on its next run.'
                    )
                    actions.loadNotes()
                } else {
                    lemonToast.success('Note added')
                }
                detailLogic?.actions.loadReportArtefacts()
            } catch (error: any) {
                lemonToast.error(error?.detail || error?.message || 'Failed to add the note')
                actions.addNoteFailed()
            } finally {
                actions.addNoteFinished()
            }
        },
        retireNote: async ({ noteId }) => {
            const teamId = teamLogic.values.currentTeamId
            if (!teamId) {
                return
            }
            const skillName = values.notes.find((note) => note.id === noteId)?.skill_name
            // Optimistic: `retiredNoteIds` marks the entry inactive at once; a failed delete undoes it.
            try {
                await signalsScoutNotesDestroy(String(teamId), noteId)
                captureScoutAction({
                    actionType: 'delete_note',
                    surface: 'report_detail',
                    skillName: skillName || null,
                    extra: { report_id: props.reportId },
                })
            } catch (error: any) {
                lemonToast.error(error?.detail || error?.message || 'Failed to retire the note')
                actions.retireNoteFailed(noteId)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadNotes()
        actions.loadScoutConfigs()
    }),
])
