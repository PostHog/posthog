import { MakeLogicType, afterMount, kea, key, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { signalsReportsList } from 'products/signals/frontend/generated/api'

import { SignalReportStatus } from '../types'
import { displayConventionalCommitTitle } from '../utils/reportPresentation'

// Mirrors `MERGEABLE_STATUSES` in products/signals/backend/report_merge.py. The API refuses a merge
// into any other status with a 409, so the picker offers only these.
export const MERGEABLE_REPORT_STATUSES: SignalReportStatus[] = [
    SignalReportStatus.POTENTIAL,
    SignalReportStatus.CANDIDATE,
    SignalReportStatus.PENDING_INPUT,
    SignalReportStatus.READY,
    SignalReportStatus.FAILED,
]

const SEARCH_DEBOUNCE_MS = 300
const CANDIDATE_LIMIT = 20

export interface MergeTargetCandidate {
    id: string
    title: string
    status: SignalReportStatus
    signalCount: number
    updatedAt: string
}

export interface MergeTargetPickerLogicProps {
    /** The report that is merged away. The picker never offers it as its own target. */
    sourceReportId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface mergeTargetPickerLogicValues {
    candidates: MergeTargetCandidate[]
    candidatesLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface mergeTargetPickerLogicActions {
    loadCandidates: (searchTerm: string) => string
    loadCandidatesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadCandidatesSuccess: (
        candidates: {
            id: string
            signalCount: number
            status: SignalReportStatus
            title: string
            updatedAt: string
        }[],
        payload?: string
    ) => {
        candidates: {
            id: string
            signalCount: number
            status: SignalReportStatus
            title: string
            updatedAt: string
        }[]
        payload?: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface mergeTargetPickerLogicMeta {
    key: string
}

export type mergeTargetPickerLogicType = MakeLogicType<
    mergeTargetPickerLogicValues,
    mergeTargetPickerLogicActions,
    MergeTargetPickerLogicProps,
    mergeTargetPickerLogicMeta
>

/** Server-side search for the live report that another report merges into. */
export const mergeTargetPickerLogic = kea<mergeTargetPickerLogicType>([
    path(['scenes', 'inbox', 'logics', 'mergeTargetPickerLogic']),
    props({} as MergeTargetPickerLogicProps),
    key((props) => props.sourceReportId),

    loaders(({ props }) => ({
        candidates: [
            [] as MergeTargetCandidate[],
            {
                loadCandidates: async (searchTerm: string, breakpoint) => {
                    await breakpoint(SEARCH_DEBOUNCE_MS)
                    const search = searchTerm.trim()
                    const response = await signalsReportsList(String(teamLogic.values.currentTeamId), {
                        status: MERGEABLE_REPORT_STATUSES.join(','),
                        limit: CANDIDATE_LIMIT,
                        ordering: '-updated_at',
                        ...(search ? { search } : {}),
                    })
                    // A newer search supersedes this one, so a slow response cannot replace newer rows.
                    breakpoint()
                    return response.results
                        .filter((report) => report.id !== props.sourceReportId)
                        .map((report) => ({
                            id: report.id,
                            title: displayConventionalCommitTitle(report.title, 'Untitled report'),
                            status: report.status as unknown as SignalReportStatus,
                            signalCount: report.signal_count,
                            updatedAt: report.updated_at,
                        }))
                },
            },
        ],
    })),

    afterMount(({ actions }) => {
        actions.loadCandidates('')
    }),
])
