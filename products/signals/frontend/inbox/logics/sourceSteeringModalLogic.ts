export const sourceSteeringModalLogic: LogicWrapper<sourceSteeringModalLogicType> = kea<sourceSteeringModalLogicType>([
    path(['scenes', 'inbox', 'logics', 'sourceSteeringModalLogic']),
    props({} as SourceSteeringModalLogicProps),
    key((logicProps) => logicProps.sourceConfig.id),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], signalSourcesLogic, ['sourceConfigs']],
        actions: [signalSourcesLogic, ['loadSourceConfigs', 'replaceSourceConfig']],
    })),
    forms(({ props: logicProps, actions, values }) => ({
        sourceSteering: {
            defaults: steeringFormDefaults(logicProps.sourceConfig),
            errors: ({ steering }: SourceSteeringFormValues) => ({
                steering:
                    steering.length > SOURCE_STEERING_MAX_LENGTH
                        ? `Rules must be ${SOURCE_STEERING_MAX_LENGTH} characters or fewer`
                        : undefined,
            }),
            submit: async (formValues: SourceSteeringFormValues) => {
                if (values.currentTeamId === null) {
                    lemonToast.error('Select a project before saving steering rules')
                    throw new Error('No project selected')
                }
                const { sourceConfig } = logicProps
                const steering = formValues.steering.trim()
                // The endpoint replaces the config object wholesale, so the whole blob goes back
                // with the steering keys merged in; a partial object would clobber source-specific
                // keys like recording_filters. The merge base is the freshest cached row rather
                // than the open-time prop snapshot, so a config change that landed while the
                // modal was open (another card's toggle, an earlier save) survives. A concurrent
                // write from another client can still be lost until the endpoint merges
                // server-side.
                const baseConfig =
                    values.sourceConfigs?.find((c: SignalSourceConfig) => c.id === sourceConfig.id)?.config ??
                    sourceConfig.config
                const config = {
                    ...baseConfig,
                    [SOURCE_STEERING_KEY]: steering,
                    [SOURCE_DEFAULT_NOT_ACTIONABLE_KEY]: formValues.defaultNotActionable,
                }
                const analyticsParams = {
                    sourceProduct: sourceConfig.source_product,
                    sourceType: sourceConfig.source_type,
                    steeringLength: steering.length,
                    defaultNotActionable: formValues.defaultNotActionable,
                }
                let updated: SignalSourceConfigApi
                try {
                    updated = await signalsSourceConfigsPartialUpdate(String(values.currentTeamId), sourceConfig.id, {
                        config,
                    })
                } catch (error) {
                    captureSignalSourceSteeringChanged({ ...analyticsParams, success: false })
                    const apiError = error instanceof ApiError ? error : null
                    lemonToast.error(apiError?.detail ?? "Couldn't save your steering rules. Please try again.")
                    throw error
                }
                captureSignalSourceSteeringChanged({ ...analyticsParams, success: true })
                lemonToast.success('Steering rules saved. They apply from the next sync.')
                // Overlay the saved row onto the cached list before the reload: if the reload is
                // slow or fails, a reopened modal would otherwise derive its form from the stale
                // config and a second save could restore the obsolete rules.
                actions.replaceSourceConfig({
                    ...sourceConfig,
                    enabled: updated.enabled ?? sourceConfig.enabled,
                    config: updated.config ?? config,
                    updated_at: updated.updated_at,
                    // The generated type widens the serializer's sync status to string | null.
                    status: (updated.status ?? null) as SignalSourceConfig['status'],
                })
                actions.loadSourceConfigs()
                logicProps.onClose()
            },
        },
    })),
])
