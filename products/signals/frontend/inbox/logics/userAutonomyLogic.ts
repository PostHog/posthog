export type userAutonomyLogicType = MakeLogicType<userAutonomyLogicValues, userAutonomyLogicActions>

/**
 * Per-user Self-driving autonomy override. Wraps the `users/@me/signal_autonomy`
 * endpoint via `api.signalUserAutonomy`. Every field here applies to reports that
 * suggest this user as reviewer: the PR auto-start priority threshold, which
 * overrides the team default when set and inherits it when `null` (see the backend
 * `_effective_threshold`); the Slack notification destination; and whether to add
 * this user as a GitHub assignee on the implementation PR.
 */
export const userAutonomyLogic = kea<userAutonomyLogicType>([
    path(['scenes', 'inbox', 'logics', 'userAutonomyLogic']),
    actions({
        setAutostartPriority: (priority: SignalReportPriority | null) => ({ priority }),
        // Fires when the threshold POST settles. Separate from the shared config reload, which a
        // Slack preference save also triggers and would otherwise release the save guard early.
        autostartPrioritySettled: true,
        // Slack notification preferences (suggested-reviewer pings for new inbox items).
        // integration + target together enable notifications; either null disables them.
        // `directMessage` is the one target the client can't name: the backend resolves it.
        updateSlackNotifications: (updates: SlackNotificationUpdates) => ({ updates }),
        // Fires when a Slack preference POST settles, releasing the save guard on its trigger.
        slackNotificationsSettled: true,
        // Opt in to being added as a GitHub assignee on PRs for reports suggesting this user.
        setGithubAssignOnPullRequest: (enabled: boolean) => ({ enabled }),
        // Fires when the GitHub assignment POST settles, releasing the switch's save guard.
        githubAssignSettled: true,
        // Ephemeral view state: whether the workspace/channel pickers are revealed. Lets a user
        // with multiple workspaces (and nothing saved yet) open the pickers to pick one.
        setSlackPickersExpanded: (expanded: boolean) => ({ expanded }),
    }),
    loaders({
        autonomyConfig: [
            null as SignalUserAutonomyConfig | null,
            {
                loadAutonomyConfig: async () => {
                    return await api.signalUserAutonomy.get()
                },
            },
        ],
    }),
    reducers({
        // Optimistically reflect the chosen priority so the select doesn't flicker
        // back to the stale value while the request is in flight.
        autonomyConfig: {
            setAutostartPriority: (state, { priority }) => ({
                ...(state ?? { autostart_priority: null }),
                autostart_priority: priority,
            }),
            setGithubAssignOnPullRequest: (state, { enabled }) => ({
                ...(state ?? { autostart_priority: null }),
                github_assign_on_pull_request: enabled,
            }),
            updateSlackNotifications: (state, { updates }) => ({
                ...(state ?? { autostart_priority: null }),
                ...('integrationId' in updates
                    ? { slack_notification_integration_id: updates.integrationId ?? null }
                    : {}),
                ...('channel' in updates ? { slack_notification_channel: updates.channel ?? null } : {}),
                ...('minPriority' in updates ? { slack_notification_min_priority: updates.minPriority ?? null } : {}),
            }),
        },
        // The threshold update runs in a listener, so `autonomyConfigLoading` (the reload loader) only
        // turns true after the POST resolves. This flag covers the POST itself so the control stays
        // disabled for the whole save window and can't fire a second, racing update.
        autostartPriorityUpdating: [
            false,
            {
                setAutostartPriority: () => true,
                autostartPrioritySettled: () => false,
            },
        ],
        // Same guard as `autostartPriorityUpdating`: the switch stays disabled for the whole save
        // window, so it cannot fire a second, racing update.
        githubAssignUpdating: [
            false,
            {
                setGithubAssignOnPullRequest: () => true,
                githubAssignSettled: () => false,
            },
        ],
        // Covers the POST itself, which `autonomyConfigLoading` only reflects once it resolves.
        slackNotificationsSaving: [
            false,
            {
                updateSlackNotifications: () => true,
                slackNotificationsSettled: () => false,
            },
        ],
        slackPickersExpanded: [
            false,
            {
                setSlackPickersExpanded: (_, { expanded }) => expanded,
            },
        ],
    }),
    listeners(({ actions }) => ({
        setAutostartPriority: async ({ priority }) => {
            let success = true
            try {
                await api.signalUserAutonomy.update({ autostart_priority: priority })
            } catch (error: any) {
                success = false
                lemonToast.error(error?.detail ?? error?.message ?? 'Failed to update auto-start threshold')
            } finally {
                actions.autostartPrioritySettled()
                captureInboxSettingsChanged({
                    setting: 'autostart_priority',
                    newValue: priority,
                    success,
                    scope: 'user',
                })
                actions.loadAutonomyConfig()
            }
        },
        setGithubAssignOnPullRequest: async ({ enabled }) => {
            let success = true
            try {
                await api.signalUserAutonomy.update({ github_assign_on_pull_request: enabled })
            } catch (error: any) {
                success = false
                lemonToast.error(error?.detail ?? error?.message ?? 'Failed to update GitHub assignment setting')
            } finally {
                actions.githubAssignSettled()
                captureInboxSettingsChanged({
                    setting: 'github_assign_on_pull_request',
                    newValue: enabled,
                    success,
                    scope: 'user',
                })
                actions.loadAutonomyConfig()
            }
        },
        updateSlackNotifications: async ({ updates }) => {
            const body = slackNotificationBody(updates)
            let success = true
            try {
                const config = await api.signalUserAutonomy.update(body)
                actions.loadAutonomyConfigSuccess(config)
            } catch (error: any) {
                success = false
                lemonToast.error(apiErrorMessage(error, 'Failed to update Slack notification setting'))
            } finally {
                actions.slackNotificationsSettled()
                captureSlackNotificationSaves(body, success)
                actions.loadAutonomyConfig()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadAutonomyConfig()
    }),
])
