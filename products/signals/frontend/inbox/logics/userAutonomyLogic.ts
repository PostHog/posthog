import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import api from 'lib/api'
import { isSlackMemberTarget } from 'lib/integrations/slackChannel'

import type { SignalUserAutonomyConfigCreateApi } from 'products/signals/frontend/generated/api.schemas'

import { captureInboxSettingsChanged } from '../inboxAnalytics'
import type { SignalReportPriority, SignalUserAutonomyConfig } from '../types'

interface SlackNotificationUpdates {
    integrationId?: number | null
    channel?: string | null
    directMessage?: true
    minPriority?: SignalReportPriority | null
}

/** Only the keys the caller passed, so unrelated fields (e.g. autostart_priority) aren't wiped. */
function slackNotificationBody(updates: SlackNotificationUpdates): SignalUserAutonomyConfigCreateApi {
    const body: SignalUserAutonomyConfigCreateApi = {}
    if ('integrationId' in updates) {
        body.slack_notification_integration_id = updates.integrationId ?? null
    }
    if ('channel' in updates) {
        body.slack_notification_channel = updates.channel ?? null
    }
    if ('minPriority' in updates) {
        body.slack_notification_min_priority = updates.minPriority ?? null
    }
    if (updates.directMessage) {
        body.slack_notification_direct_message = true
    }
    return body
}

function slackTargetKind(setting: string, value: unknown): 'direct_message' | 'channel' | null | undefined {
    if (setting === 'slack_notification_direct_message') {
        return 'direct_message'
    }
    if (setting !== 'slack_notification_channel') {
        return undefined
    }
    return typeof value === 'string' && value ? (isSlackMemberTarget(value) ? 'direct_message' : 'channel') : null
}

function captureSlackNotificationSaves(body: SignalUserAutonomyConfigCreateApi, success: boolean): void {
    for (const [setting, newValue] of Object.entries(body)) {
        // The target names the customer's own channel or account, so only its kind travels.
        const targetKind = slackTargetKind(setting, newValue)
        captureInboxSettingsChanged({
            setting,
            newValue: setting === 'slack_notification_channel' ? newValue !== null : newValue,
            success,
            scope: 'user',
            ...(targetKind === undefined ? {} : { targetKind }),
        })
    }
}

function apiErrorMessage(error: any, fallback: string): string {
    if (typeof error?.detail === 'string' && error.detail) {
        return error.detail
    }
    if (error?.data && typeof error.data === 'object') {
        for (const value of Object.values(error.data)) {
            if (Array.isArray(value) && typeof value[0] === 'string') {
                return value[0]
            }
            if (typeof value === 'string') {
                return value
            }
        }
    }
    if (typeof error?.message === 'string' && error.message) {
        return error.message
    }
    return fallback
}

