/** Write one change in a single request. Throws when the save fails. */
async function persistFilter(logic: sourceFilterModalLogicType, change: SourceFilterChange): Promise<void> {
    const { props: logicProps, actions, values } = logic
    const { sourceConfig } = logicProps
    if (values.currentTeamId === null) {
        lemonToast.error('Select a project before saving')
        throw new Error('No project selected')
    }
    const configSet: Record<string, unknown> = {}
    const configRemove: string[] = []
    if (typeof change.expression === 'string') {
        configSet[SOURCE_HOGQL_FILTER_KEY] = change.expression
    } else if (change.expression === null) {
        configRemove.push(SOURCE_HOGQL_FILTER_KEY)
    }
    if (change.teamIds !== undefined) {
        configSet[SOURCE_LINEAR_TEAM_IDS_KEY] = change.teamIds
    }
    if (Object.keys(configSet).length === 0 && configRemove.length === 0) {
        logicProps.onClose()
        return
    }

    const capture = (success: boolean): void => {
        if (change.expression !== undefined) {
            captureSignalSourceFilterExpressionChanged({
                sourceProduct: sourceConfig.source_product,
                sourceType: sourceConfig.source_type,
                action: change.expression === null ? 'removed' : 'saved',
                expressionLength: change.expression?.length ?? 0,
                success,
            })
        }
        if (change.teamIds !== undefined) {
            captureSignalSourceFiltersChanged({
                sourceProduct: sourceConfig.source_product,
                sourceType: sourceConfig.source_type,
                filter: SOURCE_LINEAR_TEAM_IDS_KEY,
                selectedCount: change.teamIds.length,
                success,
            })
        }
    }

    let updated: SignalSourceConfigApi
    try {
        updated = await signalsSourceConfigsPartialUpdate(String(values.currentTeamId), sourceConfig.id, {
            ...(Object.keys(configSet).length > 0 ? { config_set: configSet } : {}),
            ...(configRemove.length > 0 ? { config_remove: configRemove } : {}),
        })
    } catch (error) {
        capture(false)
        const expressionError = expressionErrorFrom(error)
        if (expressionError) {
            actions.setSourceFilterManualErrors({ expression: expressionError })
        } else {
            lemonToast.error(
                error instanceof ApiError && error.detail ? error.detail : "Couldn't save the filter. Try again."
            )
        }
        throw error
    }
    // Overlay the saved row before the reload, so reopening the editor before the reload lands
    // starts from what was saved rather than the stale config.
    actions.replaceSourceConfig({
        ...sourceConfig,
        enabled: updated.enabled ?? sourceConfig.enabled,
        config: updated.config ?? sourceConfig.config,
        updated_at: updated.updated_at,
        // The generated type widens the serializer's sync status to string | null.
        status: (updated.status ?? null) as SignalSourceConfig['status'],
    })
    capture(true)
    lemonToast.success(
        change.expression === null && change.teamIds === undefined
            ? 'Filter removed. It stops applying from the next sync.'
            : 'Filter saved. It applies from the next sync.'
    )
    actions.loadSourceConfigs()
    logicProps.onClose()
}

export const sourceFilterModalLogic: LogicWrapper<sourceFilterModalLogicType> = kea<sourceFilterModalLogicType>([
    path(['products', 'signals', 'inbox', 'logics', 'sourceFilterModalLogic']),
    props({} as SourceFilterModalLogicProps),
    key((logicProps) => logicProps.sourceConfig.id),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            integrationsLogic,
            ['linearIntegrations', 'integrations', 'integrationsLoading'],
            signalSourcesLogic,
            ['dataWarehouseSources'],
        ],
        actions: [
            signalSourcesLogic,
            ['loadSourceConfigs', 'replaceSourceConfig'],
            integrationsLogic,
            ['loadIntegrations', 'loadIntegrationsSuccess', 'loadIntegrationsFailure'],
        ],
    })),
    actions({
        selectField: (name: string) => ({ name }),
        removeFilter: true,
        removeFilterFinished: true,
    }),
    reducers(({ props: logicProps }) => ({
        selectedFieldName: [
            (logicProps.catalog.filter_fields[0]?.name ?? null) as string | null,
            { selectField: (_, { name }) => name },
        ],
        isRemovingFilter: [false, { removeFilter: () => true, removeFilterFinished: () => false }],
        // A failed load leaves the integrations list null, which would otherwise read as still loading.
        integrationsLoadFailed: [
            false,
            {
                loadIntegrations: () => false,
                loadIntegrationsSuccess: () => false,
                loadIntegrationsFailure: () => true,
            },
        ],
    })),
    selectors({
        savedFilter: [
            (_, p) => [p.sourceConfig],
            (sourceConfig: SignalSourceConfig): SavedSourceFilter | null => savedSourceFilter(sourceConfig.config),
        ],
        // A saved filter keeps the meaning of the catalog version it was saved on, so the editor says
        // so rather than implying the current field list applies to it.
        savedOnOlderCatalog: [
            (s, p) => [s.savedFilter, p.catalog],
            (savedFilter: SavedSourceFilter | null, catalog: SourceFilterCatalogApi): boolean =>
                !!savedFilter?.expression.trim() &&
                savedFilter.catalogVersion !== null &&
                savedFilter.catalogVersion < catalog.catalog_version,
        ],
        selectedField: [
            (s, p) => [s.selectedFieldName, p.catalog],
            (selectedFieldName: string | null, catalog: SourceFilterCatalogApi): SourceFilterCatalogFieldApi | null =>
                catalog.filter_fields.find((field) => field.name === selectedFieldName) ?? null,
        ],
        teamsEditable: [
            (_, p) => [p.sourceConfig],
            (sourceConfig: SignalSourceConfig): boolean => sourceReadsLinearTeams(sourceConfig),
        ],
        linearIntegration: [
            (s) => [s.linearIntegrations, s.dataWarehouseSources],
            (
                linearIntegrations: IntegrationType[],
                dataWarehouseSources: PaginatedResponse<ExternalDataSource> | null
            ): IntegrationType | null => syncedLinearIntegration(linearIntegrations, dataWarehouseSources),
        ],
        // A null list means the first load has not landed, which is not the same as no connection.
        integrationsUnknown: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): boolean => integrations === null,
        ],
    }),
    forms((logic) => ({
        sourceFilter: {
            defaults: formDefaults(logic.props.sourceConfig),
            // The message hangs off `teamScope` because kea-forms types an array field's error as one
            // entry per item, and this is about the list as a whole.
            errors: ({ teamScope, teamIds }: SourceFilterFormValues) => ({
                teamScope:
                    sourceReadsLinearTeams(logic.props.sourceConfig) && teamScope === 'selected' && teamIds.length === 0
                        ? 'Pick at least one team, or read all teams.'
                        : undefined,
            }),
            submit: async (values: SourceFilterFormValues) => {
                await persistFilter(logic, changeFrom(values, logic.props.sourceConfig))
            },
        },
    })),
    listeners((logic) => ({
        // A server error describes the text that was submitted, so editing the text clears it.
        setSourceFilterValue: () => {
            if (Object.keys(logic.values.sourceFilterManualErrors).length > 0) {
                logic.actions.setSourceFilterManualErrors({})
            }
        },
        removeFilter: async () => {
            try {
                await persistFilter(logic, { expression: null })
            } catch {
                // persistFilter already told the person what failed.
            } finally {
                logic.actions.removeFilterFinished()
            }
        },
    })),
    afterMount(({ props: logicProps, values, actions }) => {
        // A load that failed before this editor opened would leave the team picker waiting, so start another.
        if (
            sourceReadsLinearTeams(logicProps.sourceConfig) &&
            values.integrations === null &&
            !values.integrationsLoading
        ) {
            actions.loadIntegrations()
        }
        captureSignalSourceFilterEditorOpened({
            sourceProduct: logicProps.sourceConfig.source_product,
            sourceType: logicProps.sourceConfig.source_type,
            hasFilter: !!values.savedFilter?.expression.trim(),
        })
    }),
])
