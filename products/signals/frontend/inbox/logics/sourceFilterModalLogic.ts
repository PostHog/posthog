/** Write the expression, or remove the filter when `expression` is null. Throws when the save fails. */
async function persistFilter(logic: sourceFilterModalLogicType, expression: string | null): Promise<void> {
    const { props: logicProps, actions, values } = logic
    const { sourceConfig } = logicProps
    if (values.currentTeamId === null) {
        lemonToast.error('Select a project before saving')
        throw new Error('No project selected')
    }
    const analyticsParams = {
        sourceProduct: sourceConfig.source_product,
        sourceType: sourceConfig.source_type,
        action: expression === null ? ('removed' as const) : ('saved' as const),
        expressionLength: expression?.length ?? 0,
    }
    let updated: SignalSourceConfigApi
    try {
        updated = await signalsSourceConfigsPartialUpdate(
            String(values.currentTeamId),
            sourceConfig.id,
            expression === null
                ? { config_remove: [SOURCE_HOGQL_FILTER_KEY] }
                : { config_set: { [SOURCE_HOGQL_FILTER_KEY]: expression } }
        )
    } catch (error) {
        captureSignalSourceFilterExpressionChanged({ ...analyticsParams, success: false })
        const expressionError = expressionErrorFrom(error)
        if (expressionError) {
            actions.setSourceFilterManualErrors({ expression: expressionError })
        } else {
            lemonToast.error(
                error instanceof ApiError && error.detail ? error.detail : "Couldn't save the filter. Try again."
            )
        }
        throw error
    }
    // Overlay the saved row before the reload, so reopening the editor before the reload lands
    // starts from what was saved rather than the stale config.
    actions.replaceSourceConfig({
        ...sourceConfig,
        enabled: updated.enabled ?? sourceConfig.enabled,
        config: updated.config ?? sourceConfig.config,
        updated_at: updated.updated_at,
        // The generated type widens the serializer's sync status to string | null.
        status: (updated.status ?? null) as SignalSourceConfig['status'],
    })
    captureSignalSourceFilterExpressionChanged({ ...analyticsParams, success: true })
    lemonToast.success(
        expression === null
            ? 'Filter removed. It stops applying from the next sync.'
            : 'Filter saved. It applies from the next sync.'
    )
    actions.loadSourceConfigs()
    logicProps.onClose()
}

export const sourceFilterModalLogic: LogicWrapper<sourceFilterModalLogicType> = kea<sourceFilterModalLogicType>([
    path(['products', 'signals', 'inbox', 'logics', 'sourceFilterModalLogic']),
    props({} as SourceFilterModalLogicProps),
    key((logicProps) => logicProps.sourceConfig.id),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [signalSourcesLogic, ['loadSourceConfigs', 'replaceSourceConfig']],
    })),
    actions({
        selectField: (name: string) => ({ name }),
        removeFilter: true,
        removeFilterFinished: true,
    }),
    reducers(({ props: logicProps }) => ({
        selectedFieldName: [
            (logicProps.catalog.filter_fields[0]?.name ?? null) as string | null,
            { selectField: (_, { name }) => name },
        ],
        isRemovingFilter: [false, { removeFilter: () => true, removeFilterFinished: () => false }],
    })),
    selectors({
        savedFilter: [
            (_, p) => [p.sourceConfig],
            (sourceConfig: SignalSourceConfig): SavedSourceFilter | null => savedSourceFilter(sourceConfig.config),
        ],
        // A saved filter keeps the meaning of the catalog version it was saved on, so the editor says
        // so rather than implying the current field list applies to it.
        savedOnOlderCatalog: [
            (s, p) => [s.savedFilter, p.catalog],
            (savedFilter: SavedSourceFilter | null, catalog: SourceFilterCatalogApi): boolean =>
                !!savedFilter?.expression.trim() &&
                savedFilter.catalogVersion !== null &&
                savedFilter.catalogVersion < catalog.catalog_version,
        ],
        selectedField: [
            (s, p) => [s.selectedFieldName, p.catalog],
            (selectedFieldName: string | null, catalog: SourceFilterCatalogApi): SourceFilterCatalogFieldApi | null =>
                catalog.filter_fields.find((field) => field.name === selectedFieldName) ?? null,
        ],
    }),
    forms((logic) => ({
        sourceFilter: {
            defaults: { expression: savedSourceFilter(logic.props.sourceConfig.config)?.expression ?? '' },
            submit: async ({ expression }: SourceFilterFormValues) => {
                const trimmed = expression.trim()
                if (!trimmed && !logic.values.savedFilter) {
                    logic.props.onClose()
                    return
                }
                // Clearing the text removes the filter instead of saving a blank one.
                await persistFilter(logic, trimmed || null)
            },
        },
    })),
    listeners((logic) => ({
        // A server error describes the text that was submitted, so editing the text clears it.
        setSourceFilterValue: () => {
            if (Object.keys(logic.values.sourceFilterManualErrors).length > 0) {
                logic.actions.setSourceFilterManualErrors({})
            }
        },
        removeFilter: async () => {
            try {
                await persistFilter(logic, null)
            } catch {
                // persistFilter already told the person what failed.
            } finally {
                logic.actions.removeFilterFinished()
            }
        },
    })),
    afterMount(({ props: logicProps, values }) => {
        captureSignalSourceFilterEditorOpened({
            sourceProduct: logicProps.sourceConfig.source_product,
            sourceType: logicProps.sourceConfig.source_type,
            hasFilter: !!values.savedFilter?.expression.trim(),
        })
    }),
])
