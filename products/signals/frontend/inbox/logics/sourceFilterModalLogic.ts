const SAVE_ERROR_PREFIX = `${SOURCE_HOGQL_FILTER_KEY}: `

/**
 * The server rejects an expression with a 400 on `config`, prefixed with the config key. That
 * message belongs under the field; anything else is not about the expression.
 */
function expressionErrorFrom(error: unknown): string | null {
    if (!(error instanceof ApiError) || error.status !== 400 || !error.detail?.startsWith(SAVE_ERROR_PREFIX)) {
        return null
    }
    return error.detail.slice(SAVE_ERROR_PREFIX.length)
}

