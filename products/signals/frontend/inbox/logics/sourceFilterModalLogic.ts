export interface SourceFilterFormValues {
    expression: string
    /** Linear issues only: which teams the source reads, saved to `linear_team_ids` next to the filter. */
    teamScope: LinearTeamsScope
    teamIds: string[]
}

/** What one save writes. `undefined` leaves a key as it is. */
interface SourceFilterChange {
    /** The expression to save, or null to remove the filter. */
    expression?: string | null
    /** Linear team ids to read, where an empty list means every team. */
    teamIds?: string[]
}

export function sourceReadsLinearTeams(config: SignalSourceConfig): boolean {
    return config.source_product === SignalSourceProduct.Linear && config.source_type === SignalSourceType.Issue
}

function formDefaults(config: SignalSourceConfig): SourceFilterFormValues {
    const teamIds = linearTeamIdsFromConfig(config.config)
    return {
        expression: savedSourceFilter(config.config)?.expression ?? '',
        teamScope: teamIds.length > 0 ? 'selected' : 'all',
        teamIds,
    }
}

function sameTeams(a: string[], b: string[]): boolean {
    return a.length === b.length && a.every((id) => b.includes(id))
}

/**
 * The expression is sent only when it changed. An unchanged filter keeps the catalog version it was
 * saved on, so a teams-only save cannot fail on a field that a newer catalog dropped. Clearing the
 * text removes the filter instead of saving a blank one.
 */
function changeFrom(values: SourceFilterFormValues, config: SignalSourceConfig): SourceFilterChange {
    const change: SourceFilterChange = {}
    const trimmed = values.expression.trim()
    const saved = savedSourceFilter(config.config)
    if (trimmed && trimmed !== saved?.expression.trim()) {
        change.expression = trimmed
    } else if (!trimmed && saved) {
        change.expression = null
    }
    if (sourceReadsLinearTeams(config)) {
        const teamIds = values.teamScope === 'all' ? [] : values.teamIds
        if (!sameTeams(teamIds, linearTeamIdsFromConfig(config.config))) {
            change.teamIds = teamIds
        }
    }
    return change
}

