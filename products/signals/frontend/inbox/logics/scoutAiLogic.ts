/**
 * Sends a question from a scout page to the PostHog AI side panel. The question goes to the panel's
 * own composer as an auto-submitted seed, so the run, its follow-ups, and its history are the panel's
 * normal task flow. The scout rides along as attached context (see `scoutAiContextItems`).
 */
export const scoutAiLogic = kea<scoutAiLogicType>([
    path(['products', 'signals', 'frontend', 'inbox', 'logics', 'scoutAiLogic']),

    connect(() => ({
        values: [
            aiConsentLogic,
            ['dataProcessingAccepted', 'dataProcessingApprovalDisabledReason'],
            composerSeedLogic({ panelId: REPORT_AI_PANEL_ID }),
            ['seed'],
            runnerPanelLogic({ panelId: REPORT_AI_PANEL_ID }),
            ['activeCreation'],
        ],
        actions: [
            composerSeedLogic({ panelId: REPORT_AI_PANEL_ID }),
            ['setSeed', 'consumeSeed'],
            runnerPanelLogic({ panelId: REPORT_AI_PANEL_ID }),
            ['clearActiveCreation', 'setHistoryExpanded'],
            sidePanelStateLogic,
            ['openSidePanel'],
        ],
    })),

    actions({
        askScout: (context: ScoutChatContext, question: string) => ({ context, question }),
        setPendingSeed: (seed: ComposerSeed | null) => ({ seed }),
    }),

    reducers({
        scoutChatContext: [
            null as ScoutChatContext | null,
            {
                askScout: (_, { context }) => context,
            },
        ],
        pendingSeed: [
            null as ComposerSeed | null,
            {
                setPendingSeed: (_, { seed }) => seed,
            },
        ],
    }),

    selectors({
        aiConsentDisabledReason: [
            (s) => [s.dataProcessingAccepted, s.dataProcessingApprovalDisabledReason],
            (dataProcessingAccepted: boolean, dataProcessingApprovalDisabledReason: string | null): string | null =>
                aiConsentDisabledReason(dataProcessingAccepted, dataProcessingApprovalDisabledReason),
        ],
        // In flight from the click until the panel has created the task: first while our seed waits for
        // the panel composer, then while the panel's optimistic run has no task id yet.
        isAsking: [
            (s) => [s.seed, s.pendingSeed, s.activeCreation],
            (
                seed: ComposerSeed | null,
                pendingSeed: ComposerSeed | null,
                activeCreation: ActiveCreation | null
            ): boolean => (seed !== null && seed === pendingSeed) || (!!activeCreation && !activeCreation.taskId),
        ],
    }),

    listeners(({ actions, values }) => ({
        askScout: ({ question }) => {
            const trimmed = question.trim()
            if (!trimmed || values.isAsking) {
                return
            }
            // The composer carries this as a `disabledReason`, but Enter also submits.
            if (values.aiConsentDisabledReason) {
                lemonToast.error(values.aiConsentDisabledReason)
                return
            }
            // The panel is shared with the PostHog AI side panel. Start from its composer, so this
            // question never appends to a run or a history list left open there.
            actions.clearActiveCreation()
            actions.setHistoryExpanded(false)
            const seed: ComposerSeed = { prompt: trimmed, autoSubmit: true }
            actions.setPendingSeed(seed)
            actions.setSeed(seed)
            actions.openSidePanel(SidePanelTab.Max, SCOUT_AI_PANEL)
        },
        [sidePanelStateLogic.actionTypes.setSidePanelOpen]: ({ open }: { open: boolean }) => {
            // The panel chunk loads lazily. A close before it mounts must not send the question later.
            if (!open && values.seed && values.seed === values.pendingSeed) {
                actions.consumeSeed()
            }
        },
    })),

    beforeUnmount(({ actions, values }) => {
        if (values.seed && values.seed === values.pendingSeed) {
            actions.consumeSeed()
        }
    }),
])
