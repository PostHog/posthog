export const scoutTrialsLogic: LogicWrapper<scoutTrialsLogicType> = kea<scoutTrialsLogicType>([
    props({} as ScoutTrialsLogicProps),
    key(({ teamId, userId }) => `${teamId}:${userId}`),
    path((key) => ['products', 'signals', 'scoutTrialsLogic', key]),
    actions({
        selectConfig: (configId: string) => ({ configId }),
        setVariants: (variants: ScoutTrialVariant[]) => ({ variants }),
        updateVariant: (id: string, update: Partial<ScoutTrialVariant>) => ({ id, update }),
        addVariant: true,
        removeVariant: (id: string) => ({ id }),
        setRepeats: (repeats: number) => ({ repeats }),
        setNote: (note: string) => ({ note }),
        setBatch: (batch: ScoutTrialBatch | null) => ({ batch }),
        trackLaunches: (tracked: TrackedScoutTrial[]) => ({ tracked }),
        setResults: (results: Record<string, ScoutTrialResultApi>, errors: Record<string, string>) => ({
            results,
            errors,
        }),
        setSubmitting: (submitting: boolean) => ({ submitting }),
        setRefreshing: (refreshing: boolean) => ({ refreshing }),
        setPageError: (error: string | null) => ({ error }),
        setPollError: (error: string | null) => ({ error }),
        submitComparison: true,
        newComparison: true,
        refreshResults: (force: boolean = false) => ({ force }),
        selectResult: (launchId: string | null) => ({ launchId }),
        downloadResults: true,
        cancelRun: (launchId: string) => ({ launchId }),
        setCanceling: (launchId: string, canceling: boolean) => ({ launchId, canceling }),
    }),
    loaders(({ props, values }) => ({
        configs: [
            null as SignalScoutConfigApi[] | null,
            {
                loadConfigs: async () => signalsScoutConfigList(String(props.teamId)),
            },
        ],
        setup: [
            null as ScoutTrialSetupApi | null,
            {
                loadSetup: async (configId: string, breakpoint) => {
                    const setup = await signalsScoutConfigTrialSetup(String(props.teamId), configId)
                    breakpoint()
                    return values.selectedConfigId === configId ? setup : values.setup
                },
            },
        ],
        history: [
            null as ScoutTrialHistoryApi | null,
            {
                loadHistory: async (configId: string, breakpoint) => {
                    const history = await signalsScoutConfigTrialHistory(String(props.teamId), configId, { limit: 30 })
                    breakpoint()
                    return values.selectedConfigId === configId ? history : values.history
                },
            },
        ],
    })),
    reducers({
        setup: [null as ScoutTrialSetupApi | null, { selectConfig: () => null }],
        history: [null as ScoutTrialHistoryApi | null, { selectConfig: () => null }],
        selectedConfigId: [null as string | null, { persist: true }, { selectConfig: (_, { configId }) => configId }],
        variants: [
            [] as ScoutTrialVariant[],
            {
                setVariants: (_, { variants }) => variants,
                updateVariant: (state, { id, update }) =>
                    state.map((variant) => (variant.id === id ? { ...variant, ...update } : variant)),
                removeVariant: (state, { id }) => state.filter((variant) => variant.id !== id),
                selectConfig: () => [],
            },
        ],
        repeats: [1, { setRepeats: (_, { repeats }) => repeats }],
        note: ['', { setNote: (_, { note }) => note, selectConfig: () => '' }],
        batch: [
            null as ScoutTrialBatch | null,
            { setBatch: (_, { batch }) => batch, selectConfig: () => null, newComparison: () => null },
        ],
        tracked: [
            [] as TrackedScoutTrial[],
            { persist: true },
            {
                trackLaunches: (state, { tracked }) =>
                    [...new Map([...state, ...tracked].map((item) => [item.launchId, item])).values()].slice(-100),
            },
        ],
        results: [
            {} as Record<string, ScoutTrialResultApi>,
            {
                setResults: (state, { results }) => ({ ...state, ...results }),
            },
        ],
        resultErrors: [{} as Record<string, string>, { setResults: (_, { errors }) => errors }],
        submitting: [false, { setSubmitting: (_, { submitting }) => submitting }],
        refreshing: [false, { setRefreshing: (_, { refreshing }) => refreshing }],
        canceling: [
            [] as string[],
            {
                setCanceling: (state, { launchId, canceling }) =>
                    canceling ? [...state, launchId] : state.filter((id) => id !== launchId),
            },
        ],
        pageError: [
            null as string | null,
            {
                setPageError: (_, { error }) => error,
                selectConfig: () => null,
                newComparison: () => null,
                loadConfigsFailure: () => "Couldn't load scouts. Try again.",
                loadSetupFailure: () => "Couldn't load this scout's comparison settings. Try again.",
                loadConfigsSuccess: () => null,
                loadSetupSuccess: () => null,
            },
        ],
        pollError: [
            null as string | null,
            {
                setPollError: (_, { error }) => error,
                selectConfig: () => null,
                loadHistoryFailure: () => "Couldn't load recent runs. Refresh to try again.",
            },
        ],
        selectedLaunchId: [
            null as string | null,
            { selectResult: (_, { launchId }) => launchId, selectConfig: () => null },
        ],
    }),
    selectors({
        totalRuns: [
            (s) => [s.variants, s.repeats],
            (variants: ScoutTrialVariant[], repeats: number): number => variants.length * repeats,
        ],
        formError: [
            (s) => [s.setup, s.variants, s.repeats],
            (setup: ScoutTrialSetupApi | null, variants: ScoutTrialVariant[], repeats: number): string | null =>
                trialFormError(setup, variants, repeats),
        ],
        hasUnaccepted: [
            (s) => [s.batch],
            (batch: ScoutTrialBatch | null): boolean => !!batch?.submissions.some((submission) => !submission.accepted),
        ],
        selectedResult: [
            (s) => [s.selectedLaunchId, s.results],
            (launchId: string | null, results: Record<string, ScoutTrialResultApi>): ScoutTrialResultApi | null =>
                launchId ? (results[launchId] ?? null) : null,
        ],
        rows: [
            (s) => [s.selectedConfigId, s.tracked, s.history, s.results, s.resultErrors, s.batch],
            (
                configId: string | null,
                tracked: TrackedScoutTrial[],
                history: ScoutTrialHistoryApi | null,
                results: Record<string, ScoutTrialResultApi>,
                errors: Record<string, string>,
                batch: ScoutTrialBatch | null
            ): ScoutTrialRow[] => {
                const relevantHistory = history?.results ?? []
                const ids = [
                    ...new Set([
                        ...(batch?.submissions.map((entry) => entry.request.launch_id) ?? []),
                        ...relevantHistory.map((entry) => entry.launch_id),
                        ...tracked
                            .filter((entry) => entry.configId === configId)
                            .map((entry) => entry.launchId)
                            .reverse(),
                    ]),
                ]
                return ids.map((launchId) => {
                    const result = results[launchId] ?? null
                    const saved = relevantHistory.find((entry) => entry.launch_id === launchId)
                    const submission = batch?.submissions.find((entry) => entry.request.launch_id === launchId)
                    return {
                        launchId,
                        variant: saved?.variant || submission?.request.variant || 'Saved run',
                        model: result?.model || saved?.model || submission?.request.model || '',
                        effort:
                            result?.reasoning_effort ||
                            saved?.reasoning_effort ||
                            submission?.request.reasoning_effort ||
                            '',
                        status:
                            result?.status ||
                            saved?.status ||
                            (submission?.accepted ? 'pending' : submission?.error ? 'submission_failed' : 'unknown'),
                        startedAt: result?.started_at || saved?.started_at || null,
                        error: result?.error || submission?.error || errors[launchId] || null,
                        result,
                    }
                })
            },
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        loadConfigsSuccess: ({ configs }) => {
            if (!configs?.length) {
                return
            }
            actions.selectConfig(
                configs.some((config) => config.id === values.selectedConfigId)
                    ? values.selectedConfigId!
                    : configs[0].id
            )
        },
        selectConfig: ({ configId }) => {
            actions.loadSetup(configId)
            actions.loadHistory(configId)
            actions.refreshResults()
        },
        loadSetupSuccess: ({ setup }) => {
            if (setup) {
                actions.setVariants(initialTrialVariants(setup))
            }
        },
        loadHistorySuccess: ({ history }) => {
            if (history && values.selectedConfigId) {
                actions.trackLaunches(
                    history.results.map((entry) => ({ configId: values.selectedConfigId!, launchId: entry.launch_id }))
                )
                actions.refreshResults()
            }
        },
        addVariant: () => {
            const baseline = values.variants[0]
            if (baseline && values.variants.length < 10) {
                actions.setVariants([
                    ...values.variants,
                    {
                        ...baseline,
                        id: uuid(),
                        label: `Variant ${values.variants.length}`,
                        prompt: '',
                        replacePrompt: false,
                    },
                ])
            }
        },
        newComparison: () => {
            if (values.selectedConfigId) {
                actions.loadSetup(values.selectedConfigId)
            }
        },
        submitComparison: async () => {
            if (cache.submitting || !values.selectedConfigId || (!values.batch && values.formError)) {
                return
            }
            cache.submitting = true
            actions.setSubmitting(true)
            actions.setPageError(null)
            const manager = cache.disposables
            const context = getContext()
            const stillMounted = (): boolean => !manager.isDisposed && getContext() === context
            let batch =
                values.batch ??
                createTrialBatch(values.selectedConfigId, values.variants, values.repeats, values.note, uuid)
            const saveBatch = (): void => {
                if (stillMounted()) {
                    actions.setBatch({ ...batch, submissions: [...batch.submissions] })
                }
            }
            saveBatch()
            actions.trackLaunches(
                batch.submissions.map((entry) => ({ configId: batch.configId, launchId: entry.request.launch_id }))
            )
            const submit = async (index: number): Promise<boolean> => {
                const entry = batch.submissions[index]
                if (entry.accepted) {
                    return true
                }
                try {
                    const started = await signalsScoutConfigTrial(String(props.teamId), batch.configId, entry.request)
                    batch = {
                        ...batch,
                        contextId: started.context_id,
                        submissions: batch.submissions.map((item, i) =>
                            i === index ? { ...item, accepted: true, error: null } : item
                        ),
                    }
                    saveBatch()
                    return true
                } catch {
                    batch = {
                        ...batch,
                        submissions: batch.submissions.map((item, i) =>
                            i === index
                                ? { ...item, error: 'Submission was not confirmed. Retry uses the same run ID.' }
                                : item
                        ),
                    }
                    saveBatch()
                    return false
                }
            }
            try {
                if (!batch.contextId && !(await submit(0))) {
                    return
                }
                batch = {
                    ...batch,
                    submissions: batch.submissions.map((entry, index) =>
                        index === 0 ? entry : { ...entry, request: { ...entry.request, context_id: batch.contextId! } }
                    ),
                }
                saveBatch()
                await Promise.all(batch.submissions.map((_, index) => submit(index)))
            } finally {
                cache.submitting = false
                if (stillMounted()) {
                    actions.setSubmitting(false)
                    actions.refreshResults()
                    actions.loadHistory(batch.configId)
                }
            }
        },
        refreshResults: async ({ force }) => {
            if (cache.refreshing || !values.selectedConfigId) {
                return
            }
            const configId = values.selectedConfigId
            const entries = values.tracked.filter((entry) => {
                const result = values.results[entry.launchId]
                return (
                    entry.configId === configId &&
                    (force ||
                        !result ||
                        result.status === 'unknown' ||
                        trialIsActive(result.status) ||
                        trialIsActive(result.task_status ?? ''))
                )
            })
            if (!entries.length) {
                return
            }
            cache.refreshing = true
            actions.setRefreshing(true)
            const manager = cache.disposables
            const context = getContext()
            const responses = await Promise.allSettled(
                entries.map((entry) =>
                    signalsScoutConfigTrialResult(String(props.teamId), configId, { launch_id: entry.launchId })
                )
            )
            cache.refreshing = false
            if (manager.isDisposed || getContext() !== context) {
                return
            }
            const results: Record<string, ScoutTrialResultApi> = {}
            const errors: Record<string, string> = {}
            responses.forEach((response, index) => {
                if (response.status === 'fulfilled') {
                    results[entries[index].launchId] = response.value
                } else {
                    errors[entries[index].launchId] =
                        'Status unavailable. Refresh to check whether this run was accepted.'
                }
            })
            actions.setResults(results, errors)
            actions.setRefreshing(false)
            actions.setPollError(
                Object.keys(errors).length
                    ? 'Some run statuses could not be loaded. Existing results stay visible.'
                    : null
            )
            if (values.selectedConfigId !== configId) {
                actions.refreshResults()
            }
        },
        downloadResults: () => {
            const results = values.rows.flatMap((row) => (row.result ? [{ variant: row.variant, ...row.result }] : []))
            downloadFile(
                new File(
                    [JSON.stringify({ config_id: values.selectedConfigId, results }, null, 2)],
                    'scout-comparison-results.json',
                    { type: 'application/json' }
                )
            )
        },
        cancelRun: async ({ launchId }) => {
            const result = values.results[launchId]
            if (!result?.task_id || !result.task_run_id || values.canceling.includes(launchId)) {
                return
            }
            actions.setCanceling(launchId, true)
            const manager = cache.disposables
            const context = getContext()
            try {
                await tasksRunsCancelCreate(String(props.teamId), result.task_id, result.task_run_id)
            } catch {
                if (!manager.isDisposed && getContext() === context) {
                    actions.setPageError("Couldn't stop this run. Refresh its status and try again.")
                }
            } finally {
                if (!manager.isDisposed && getContext() === context) {
                    actions.setCanceling(launchId, false)
                    actions.refreshResults()
                }
            }
        },
    })),
    afterMount(({ actions, values, cache }) => {
        actions.loadConfigs()
        cache.disposables.add(() => {
            const poll = window.setInterval(() => {
                if (
                    values.rows.some(
                        (row) =>
                            trialIsActive(row.status) ||
                            row.status === 'unknown' ||
                            trialIsActive(row.result?.task_status ?? '')
                    )
                ) {
                    actions.refreshResults()
                    if (values.selectedConfigId && !values.historyLoading) {
                        actions.loadHistory(values.selectedConfigId)
                    }
                }
            }, TRIAL_POLL_INTERVAL_MS)
            return () => window.clearInterval(poll)
        })
    }),
])
