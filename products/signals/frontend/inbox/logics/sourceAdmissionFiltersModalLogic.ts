export const sourceAdmissionFiltersModalLogic = kea<sourceAdmissionFiltersModalLogicType>([
    path(['scenes', 'inbox', 'logics', 'sourceAdmissionFiltersModalLogic']),
    props({} as SourceAdmissionFiltersModalLogicProps),
    key((logicProps) => logicProps.sourceConfig.id),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], signalSourcesLogic, ['sourceConfigs']],
        actions: [signalSourcesLogic, ['loadSourceConfigs', 'replaceSourceConfig']],
    })),
    actions({
        clearPreview: true,
    }),
    loaders(({ props: logicProps, values }) => ({
        preview: [
            null as SignalSourceAdmissionPreviewApi | null,
            {
                loadPreview: async () => {
                    if (values.currentTeamId === null) {
                        return null
                    }
                    return await signalsSourceConfigsAdmissionPreviewCreate(
                        String(values.currentTeamId),
                        logicProps.sourceConfig.id,
                        // The cast drops the group type: the generated request types the tree as an open object.
                        {
                            admission_rules: admissionRulesFromForm(
                                values.admissionFilters,
                                values.fields
                            ) as unknown as Record<string, unknown> | null,
                        }
                    )
                },
            },
        ],
    })),
    reducers({
        preview: {
            clearPreview: () => null,
        },
        previewError: [
            null as string | null,
            {
                loadPreview: () => null,
                loadPreviewSuccess: () => null,
                loadPreviewFailure: (_, { error, errorObject }) =>
                    (errorObject instanceof ApiError ? errorObject.detail : null) ??
                    error ??
                    "Couldn't load the preview. Try again.",
                clearPreview: () => null,
            },
        ],
    }),
    selectors({
        fields: [
            () => [(_, logicProps: SourceAdmissionFiltersModalLogicProps) => logicProps.sourceConfig],
            (sourceConfig: SignalSourceConfig): AdmissionRuleFieldApi[] => sourceConfig.admission_rule_fields ?? [],
        ],
        // The stored tree uses nested groups, which this form can't show. Saving replaces them.
        hasUnsupportedStoredRules: [
            () => [(_, logicProps: SourceAdmissionFiltersModalLogicProps) => logicProps.sourceConfig],
            (sourceConfig: SignalSourceConfig): boolean => admissionFormFromConfig(sourceConfig.config) === null,
        ],
    }),
    forms(({ props: logicProps, actions, values }) => ({
        admissionFilters: {
            defaults: admissionFormFromConfig(logicProps.sourceConfig.config) ?? {
                match: 'AND' as const,
                rows: [],
            },
            // Each row's message hangs off `field` (a string) because kea-forms types an array
            // field's error as an array, and this message is about the row as a whole.
            errors: ({ rows }: AdmissionFiltersFormValues) => ({
                rows: rows.map((row) => ({ field: admissionRowError(row) })),
            }),
            submit: async (formValues: AdmissionFiltersFormValues) => {
                if (values.currentTeamId === null) {
                    lemonToast.error('Select a project before saving')
                    throw new Error('No project selected')
                }
                const { sourceConfig } = logicProps
                const analyticsParams = {
                    sourceProduct: sourceConfig.source_product,
                    sourceType: sourceConfig.source_type,
                    filter: SOURCE_ADMISSION_RULES_KEY,
                    selectedCount: formValues.rows.length,
                }
                // The endpoint replaces the config object wholesale, so the whole blob goes back with
                // the rules merged in. The freshest cached row keeps keys like `linear_team_ids` and
                // `steering` that changed while the modal was open.
                const baseConfig =
                    values.sourceConfigs?.find((c: SignalSourceConfig) => c.id === sourceConfig.id)?.config ??
                    sourceConfig.config
                const config = {
                    ...baseConfig,
                    [SOURCE_ADMISSION_RULES_KEY]: admissionRulesFromForm(formValues, values.fields),
                }
                let updated: SignalSourceConfigApi
                try {
                    updated = await signalsSourceConfigsPartialUpdate(String(values.currentTeamId), sourceConfig.id, {
                        config,
                    })
                } catch (error) {
                    captureSignalSourceFiltersChanged({ ...analyticsParams, success: false })
                    const apiError = error instanceof ApiError ? error : null
                    lemonToast.error(apiError?.detail ?? "Couldn't save your filters. Try again.")
                    throw error
                }
                actions.replaceSourceConfig({
                    ...sourceConfig,
                    enabled: updated.enabled ?? sourceConfig.enabled,
                    config: updated.config ?? config,
                    updated_at: updated.updated_at,
                    status: (updated.status ?? null) as SignalSourceConfig['status'],
                })
                captureSignalSourceFiltersChanged({ ...analyticsParams, success: true })
                lemonToast.success(
                    formValues.rows.length === 0
                        ? 'Filters cleared. Every issue is eligible from the next sync.'
                        : 'Filters saved. They apply from the next sync.'
                )
                actions.loadSourceConfigs()
                logicProps.onClose()
            },
        },
    })),
    listeners(({ actions }) => ({
        // A preview of different rules would mislead, so any edit drops it.
        setAdmissionFiltersValue: () => actions.clearPreview(),
        setAdmissionFiltersValues: () => actions.clearPreview(),
    })),
])
