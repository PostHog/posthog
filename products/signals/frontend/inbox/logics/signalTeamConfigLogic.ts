/**
 * Team-level Self-driving config (singleton per team). Wraps the
 * `signals/team_config` endpoint via `api.signalTeamConfig`. Surfaces the
 * team-wide default PR auto-start threshold (which seeds every user's effective
 * threshold until they set a personal override in `userAutonomyLogic`) and the
 * team-wide default Slack notification channel, where every actionable report is
 * posted regardless of whether a suggested reviewer resolves. The auto-start
 * field is non-nullable (P0–P4), so unlike the per-user override there is no
 * "Never" option; the channel is nullable and `null` disables the team default.
 */
export const signalTeamConfigLogic = kea<signalTeamConfigLogicType>([
    path(['scenes', 'inbox', 'logics', 'signalTeamConfigLogic']),
    actions({
        // Declared up front so the loader below adopts this signature instead of generating a
        // single-payload one: callers say `patchTeamConfig({ autostart_enabled: false })`.
        patchTeamConfig: (patch: Partial<SignalTeamConfig>, clearDraftOnSuccess: boolean = false) => ({
            patch,
            clearDraftOnSuccess,
        }),
        setDraftBaseBranchIntegrationId: (integrationId: number | null) => ({ integrationId }),
        setDraftBaseBranchRepo: (repo: string) => ({ repo }),
        setDraftBaseBranchBranch: (branch: string) => ({ branch }),
        clearDraftBaseBranch: true,
        addBaseBranchOverride: true,
        updateBaseBranchOverride: (repo: string, branch: string) => ({ repo, branch }),
        removeBaseBranchOverride: (repo: string) => ({ repo }),
        setDraftMaxReportsPerDay: (value: number | null) => ({ value }),
        saveDraftMaxReportsPerDay: true,
    }),
    loaders(() => {
        // Every patch of `autostart_base_branches` sends the whole map, so two in flight at once let the
        // server settle on whichever lands last rather than whichever was asked for last.
        let updateQueue: Promise<unknown> = Promise.resolve()

        return {
            teamConfig: [
                null as SignalTeamConfig | null,
                {
                    loadTeamConfig: async () => {
                        return await api.signalTeamConfig.get()
                    },
                    // Partial update of the singleton, e.g. `{ default_slack_notification_channel: null }`
                    // to clear the team channel. One action serves every patchable field.
                    patchTeamConfig: async ({
                        patch,
                    }: {
                        patch: Partial<SignalTeamConfig>
                        clearDraftOnSuccess: boolean
                    }) => {
                        const update = updateQueue.then(() => api.signalTeamConfig.update(patch))
                        updateQueue = update.then(
                            () => undefined,
                            () => undefined
                        )
                        return await update
                    },
                },
            ],
        }
    }),
    reducers({
        // Optimistically reflect the patched values so the controls don't flicker
        // back to the stale ones while the request is in flight.
        teamConfig: {
            patchTeamConfig: (state, { patch }) => (state ? { ...state, ...patch } : state),
        },
        draftBaseBranchIntegrationId: [
            null as number | null,
            {
                setDraftBaseBranchIntegrationId: (_, { integrationId }) => integrationId,
            },
        ],
        draftBaseBranchRepo: [
            '',
            {
                setDraftBaseBranchRepo: (_, { repo }) => repo,
                setDraftBaseBranchIntegrationId: () => '',
                clearDraftBaseBranch: () => '',
            },
        ],
        draftBaseBranchBranch: [
            '',
            {
                setDraftBaseBranchBranch: (_, { branch }) => branch,
                setDraftBaseBranchRepo: () => '',
                setDraftBaseBranchIntegrationId: () => '',
                clearDraftBaseBranch: () => '',
            },
        ],
        // A save is in flight while this is above zero. Tracked explicitly rather than read off
        // teamConfigLoading, because that flag also flips for the initial load and the background
        // tab-return refresh (both plain GETs), neither of which should disable the save controls.
        patchesInFlight: [
            0,
            {
                patchTeamConfig: (state: number) => state + 1,
                patchTeamConfigSuccess: (state: number) => Math.max(0, state - 1),
                patchTeamConfigFailure: (state: number) => Math.max(0, state - 1),
            },
        ],
        // The daily-limit input's draft. Seeded from the server once on first load (see the
        // loadTeamConfigSuccess listener) and re-anchored only when its own save settles, so saving
        // an unrelated setting on this shared singleton logic never wipes an unsaved edit.
        draftMaxReportsPerDay: [
            null as number | null,
            {
                // A cleared number LemonInput emits NaN, which is never a valid draft — treat it as
                // null ("no limit") so the field can be reset to unlimited.
                setDraftMaxReportsPerDay: (_, { value }) => (value != null && Number.isNaN(value) ? null : value),
                patchTeamConfigSuccess: (state, { teamConfig, payload }) =>
                    payload?.patch && 'max_reports_per_day' in payload.patch
                        ? (teamConfig?.max_reports_per_day ?? null)
                        : state,
            },
        ],
    }),
    selectors({
        // Master switch for autonomous inbox PRs: only an explicit false disables
        // auto-start, so a team that never touched the setting stays on.
        autostartEnabled: [
            (s) => [s.teamConfig],
            (teamConfig: SignalTeamConfig | null): boolean => teamConfig?.autostart_enabled !== false,
        ],
        defaultAutostartPriority: [
            (s) => [s.teamConfig],
            (teamConfig: SignalTeamConfig | null): SignalReportPriority =>
                teamConfig?.default_autostart_priority ?? 'P4',
        ],
        baseBranchOverrides: [
            (s) => [s.teamConfig],
            (teamConfig: SignalTeamConfig | null): BaseBranchOverride[] =>
                Object.entries(teamConfig?.autostart_base_branches ?? {})
                    .map(([repo, branch]) => ({ repo, branch }))
                    .sort((a, b) => a.repo.localeCompare(b.repo)),
        ],
        maxReportsPerDay: [
            (s) => [s.teamConfig],
            (teamConfig: SignalTeamConfig | null): number | null => teamConfig?.max_reports_per_day ?? null,
        ],
        reportsGeneratedToday: [
            (s) => [s.teamConfig],
            (teamConfig: SignalTeamConfig | null): number => teamConfig?.reports_generated_today ?? 0,
        ],
        dailyReportLimitReached: [
            (s) => [s.teamConfig],
            (teamConfig: SignalTeamConfig | null): boolean => teamConfig?.daily_report_limit_reached === true,
        ],
        // True only while a save (patch) is in flight. Deliberately not derived from teamConfigLoading:
        // the shared loader also raises that flag for the initial load and the background tab-return
        // refresh, and neither should disable the save controls or show a "Saving changes" state.
        teamConfigUpdating: [(s) => [s.patchesInFlight], (patchesInFlight: number): boolean => patchesInFlight > 0],
        // Doubles as the save button's tooltip, same single-statement pattern as
        // addBaseBranchOverrideDisabledReason below.
        saveMaxReportsPerDayDisabledReason: [
            (s) => [s.draftMaxReportsPerDay, s.maxReportsPerDay],
            (draftMaxReportsPerDay: number | null, maxReportsPerDay: number | null): string | null => {
                if (
                    draftMaxReportsPerDay !== null &&
                    (!Number.isInteger(draftMaxReportsPerDay) || draftMaxReportsPerDay < 1)
                ) {
                    return 'Enter a whole number of at least 1'
                }
                return draftMaxReportsPerDay === maxReportsPerDay ? 'No changes to save' : null
            },
        ],
        // Doubles as the add button's tooltip, so what blocks the add is stated once rather than
        // derived separately for the guard and for the copy.
        addBaseBranchOverrideDisabledReason: [
            (s) => [s.draftBaseBranchRepo, s.draftBaseBranchBranch],
            (draftBaseBranchRepo: string, draftBaseBranchBranch: string): string | null => {
                if (!isRepositoryKey(draftBaseBranchRepo)) {
                    return 'Choose a repository first'
                }
                return draftBaseBranchBranch.trim() ? null : 'Choose a branch first'
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        // The patch is applied optimistically before these listeners run, so the setting names are
        // taken off the request rather than read back off state. A FIFO is enough to pair a
        // success/failure with its patch: the loader serializes the requests, so they settle in send order.
        const captureSettled = (success: boolean): void => {
            const patch: Partial<SignalTeamConfig> | undefined = cache.pendingSettingPatches?.shift()
            for (const [setting, newValue] of Object.entries(patch ?? {})) {
                captureInboxSettingsChanged({ setting, newValue, success, scope: 'team' })
            }
        }

        return {
            patchTeamConfig: ({ patch }) => {
                ;(cache.pendingSettingPatches ??= []).push(patch)
            },
            addBaseBranchOverride: () => {
                if (values.addBaseBranchOverrideDisabledReason) {
                    return
                }
                actions.patchTeamConfig(
                    {
                        autostart_base_branches: {
                            ...values.teamConfig?.autostart_base_branches,
                            [values.draftBaseBranchRepo.trim().toLowerCase()]: values.draftBaseBranchBranch.trim(),
                        },
                    },
                    true
                )
            },
            updateBaseBranchOverride: ({ repo, branch }) => {
                const trimmed = branch.trim()
                if (!trimmed || values.teamConfig?.autostart_base_branches?.[repo] === trimmed) {
                    return
                }
                actions.patchTeamConfig({
                    autostart_base_branches: { ...values.teamConfig?.autostart_base_branches, [repo]: trimmed },
                })
            },
            removeBaseBranchOverride: ({ repo }) => {
                const next = { ...values.teamConfig?.autostart_base_branches }
                delete next[repo]
                actions.patchTeamConfig({ autostart_base_branches: next })
            },
            saveDraftMaxReportsPerDay: () => {
                // Guard the Enter path against double-submission: the Save button disables itself while
                // a save runs, but LemonInput's onPressEnter does not, so also bail while any request
                // for this singleton is in flight. A save must not race a concurrent GET or PATCH — they
                // share one loader key with no ordering, so a late response could clobber the saved value.
                if (values.saveMaxReportsPerDayDisabledReason || values.teamConfigLoading) {
                    return
                }
                actions.patchTeamConfig({ max_reports_per_day: values.draftMaxReportsPerDay })
            },
            loadTeamConfigSuccess: ({ teamConfig }) => {
                // Seed the draft from the server only on the first load, so a later reload (e.g. the
                // one triggered when an unrelated setting's save fails) can't wipe an unsaved edit.
                if (!cache.maxReportsDraftSeeded) {
                    cache.maxReportsDraftSeeded = true
                    actions.setDraftMaxReportsPerDay(teamConfig?.max_reports_per_day ?? null)
                }
            },
            patchTeamConfigSuccess: ({ payload }) => {
                captureSettled(true)
                if (payload?.clearDraftOnSuccess) {
                    actions.clearDraftBaseBranch()
                }
            },
            patchTeamConfigFailure: ({ error, errorObject }) => {
                captureSettled(false)
                lemonToast.error(errorObject?.detail ?? error ?? 'Failed to update team self-driving settings')
                // The optimistic value is now a lie, and the server holds the truth about what stuck.
                actions.loadTeamConfig()
            },
        }
    }),
    afterMount(({ actions, values, cache }) => {
        actions.loadTeamConfig()
        // Refresh on return to the tab: reports keep generating in the background, so the
        // daily-limit count and reached-banner would otherwise stay stale until a reload or save.
        cache.disposables.add(
            () => {
                const handler = (): void => {
                    if (document.visibilityState !== 'visible' || values.teamConfigLoading) {
                        return
                    }
                    const now = Date.now()
                    if (now - (cache.lastVisibilityRefetch ?? 0) < VISIBILITY_REFETCH_THROTTLE_MS) {
                        return
                    }
                    cache.lastVisibilityRefetch = now
                    actions.loadTeamConfig()
                }
                document.addEventListener('visibilitychange', handler)
                return () => document.removeEventListener('visibilitychange', handler)
            },
            'refreshOnTabReturn',
            { pauseOnPageHidden: false }
        )
    }),
])
