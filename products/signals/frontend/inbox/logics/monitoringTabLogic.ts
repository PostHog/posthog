import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { featureFlagLogic, type FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { projectLogic } from 'scenes/projectLogic'

import { signalsReportsList, signalsReportsRefreshMetricsCreate } from '../../generated/api'
import type { SignalReportListApi, SignalReportMetricSnapshotsApi } from '../../generated/api.schemas'
import { captureInboxPanelViewed, captureMonitoringRowExpanded, captureMonitoringScopeChanged } from '../inboxAnalytics'
import { monitoringRowStatus, sortByVerdict } from '../utils/monitoringTimeline'
import { isReportMetricsEnabled, mergeReportMetricSnapshots, reportNeedsMetricRefresh } from '../utils/reportMetrics'

/** pinned: values of the list API's `connected` param, also stored in the user's saved scope. */
export type MonitoringConnection = 'assigned' | 'suggested_reviewer'
export const MONITORING_CONNECTIONS: MonitoringConnection[] = ['assigned', 'suggested_reviewer']

export interface MonitoringScope {
    everyone: boolean
    connections: MonitoringConnection[]
}

export const DEFAULT_MONITORING_SCOPE: MonitoringScope = { everyone: false, connections: MONITORING_CONNECTIONS }

const PAGE_LIMIT = 100
const METRIC_REFRESH_PAGE_SIZE = 20

export interface MonitoringPage {
    results: SignalReportListApi[]
    count: number
    hasMore: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface monitoringTabLogicValues {
    currentProjectId: number | null
    expandedReportIds: string[]
    featureFlags: FeatureFlagsSet
    loadFailed: boolean
    loadedAt: number | null
    page: MonitoringPage | null
    pageLoading: boolean
    reports: SignalReportListApi[] | null
    scope: MonitoringScope
    sortedReports: SignalReportListApi[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface monitoringTabLogicActions {
    applyMetricSnapshots: (snapshots: SignalReportMetricSnapshotsApi[]) => {
        snapshots: SignalReportMetricSnapshotsApi[]
    }
    loadMore: () => { value: true }
    loadMoreReports: (_: void) => void
    loadMoreReportsFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadMoreReportsSuccess: (
        page: MonitoringPage | null,
        payload?: void
    ) => { page: MonitoringPage | null; payload?: void }
    loadReports: (_: void) => void
    loadReportsFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadReportsSuccess: (page: MonitoringPage | null, payload?: void) => { page: MonitoringPage | null; payload?: void }
    refreshReportMetrics: (reportIds: string[]) => { reportIds: string[] }
    setScope: (scope: MonitoringScope) => { scope: MonitoringScope }
    toggleExpanded: (reportId: string) => { reportId: string }
}

export type monitoringTabLogicType = MakeLogicType<monitoringTabLogicValues, monitoringTabLogicActions>

export function monitoringListParams(
    scope: MonitoringScope,
    offset = 0
): { view: string; connected?: string; limit: number; offset: number; include_source_metadata: boolean } {
    return {
        view: 'monitoring_recent',
        ...(scope.everyone ? {} : { connected: scope.connections.join(',') }),
        limit: PAGE_LIMIT,
        offset,
        include_source_metadata: false,
    }
}

function staleMetricReportIds(reports: SignalReportListApi[]): string[] {
    const now = Date.now()
    return reports
        .filter((report) => !report.monitoring_outcome && reportNeedsMetricRefresh(report, now))
        .map((report) => report.id)
}

export const monitoringTabLogic = kea<monitoringTabLogicType>([
    path(['products', 'signals', 'inbox', 'logics', 'monitoringTabLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']] })),
    actions({
        setScope: (scope: MonitoringScope) => ({ scope }),
        toggleExpanded: (reportId: string) => ({ reportId }),
        loadMore: true,
        refreshReportMetrics: (reportIds: string[]) => ({ reportIds }),
        applyMetricSnapshots: (snapshots: SignalReportMetricSnapshotsApi[]) => ({ snapshots }),
    }),
    loaders(({ values }) => {
        const fetchPage = async (offset: number, breakpoint: () => void): Promise<MonitoringPage | null> => {
            if (values.currentProjectId == null) {
                return null
            }
            if (!values.scope.everyone && values.scope.connections.length === 0) {
                return { results: [], count: 0, hasMore: false }
            }
            try {
                const response = await signalsReportsList(
                    String(values.currentProjectId),
                    monitoringListParams(values.scope, offset)
                )
                breakpoint()
                return { results: response.results, count: response.count, hasMore: !!response.next }
            } catch (error) {
                // A request for a scope the user already left must not replace the newer page with an error.
                breakpoint()
                throw error
            }
        }
        return {
            page: [
                null as MonitoringPage | null,
                {
                    loadReports: async (_, breakpoint) => fetchPage(0, breakpoint),
                    loadMoreReports: async (_, breakpoint) => {
                        const current = values.page
                        const next = await fetchPage(current?.results.length ?? 0, breakpoint)
                        if (!current || !next) {
                            return next
                        }
                        const seen = new Set(current.results.map((report) => report.id))
                        return {
                            ...next,
                            results: [...current.results, ...next.results.filter((report) => !seen.has(report.id))],
                        }
                    },
                    applyMetricSnapshots: ({ snapshots }) =>
                        values.page && {
                            ...values.page,
                            results: values.page.results.map((report) => mergeReportMetricSnapshots(report, snapshots)),
                        },
                },
            ],
        }
    }),
    reducers({
        scope: [DEFAULT_MONITORING_SCOPE, { persist: true }, { setScope: (_, { scope }) => scope }],
        expandedReportIds: [
            [] as string[],
            {
                toggleExpanded: (ids, { reportId }) =>
                    ids.includes(reportId) ? ids.filter((id) => id !== reportId) : [...ids, reportId],
            },
        ],
        loadFailed: [
            false,
            {
                loadReports: () => false,
                loadReportsSuccess: () => false,
                loadReportsFailure: () => true,
            },
        ],
        // A reading that came due after the rows were read may have run since, so it is not called overdue.
        loadedAt: [null as number | null, { loadReportsSuccess: () => Date.now() }],
    }),
    selectors({
        reports: [(s) => [s.page], (page): SignalReportListApi[] | null => page?.results ?? null],
        sortedReports: [(s) => [s.reports], (reports): SignalReportListApi[] => sortByVerdict(reports ?? [])],
    }),
    listeners(({ actions, values, cache }) => ({
        setScope: ({ scope }) => {
            captureMonitoringScopeChanged(scope)
            // Clear the previous scope's rows, so neither they nor its empty state show under the new scope.
            actions.loadReportsSuccess(null)
            actions.loadReports()
        },
        loadMore: () => {
            if (values.page?.hasMore && !values.pageLoading) {
                actions.loadMoreReports()
            }
        },
        loadReportsSuccess: ({ page }) => {
            if (!page) {
                return
            }
            if (!cache.panelViewCaptured) {
                cache.panelViewCaptured = true
                captureInboxPanelViewed({ panel: 'monitoring', itemCount: page.results.length })
            }
            actions.refreshReportMetrics(staleMetricReportIds(page.results))
        },
        loadMoreReportsSuccess: ({ page }) => {
            actions.refreshReportMetrics(staleMetricReportIds(page?.results ?? []))
        },
        refreshReportMetrics: async ({ reportIds }, breakpoint) => {
            if (!isReportMetricsEnabled(values.featureFlags) || values.currentProjectId == null) {
                return
            }
            for (let offset = 0; offset < reportIds.length; offset += METRIC_REFRESH_PAGE_SIZE) {
                let response: Awaited<ReturnType<typeof signalsReportsRefreshMetricsCreate>>
                try {
                    response = await signalsReportsRefreshMetricsCreate(String(values.currentProjectId), {
                        report_ids: reportIds.slice(offset, offset + METRIC_REFRESH_PAGE_SIZE),
                    })
                } catch {
                    return
                }
                breakpoint()
                actions.applyMetricSnapshots([...response.reports])
            }
        },
        toggleExpanded: ({ reportId }) => {
            const report = values.reports?.find((candidate) => candidate.id === reportId)
            if (report && values.expandedReportIds.includes(reportId)) {
                captureMonitoringRowExpanded({
                    reportId,
                    status: monitoringRowStatus(report, Date.now()).label,
                    finished: !!report.monitoring_outcome,
                })
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadReports()
    }),
])
