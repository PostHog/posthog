import { MakeLogicType, actions, kea, path, reducers } from 'kea'

import type { ScoutSurface } from '../inboxAnalytics'
import type { ScoutCreateInitialValues } from './scoutCreateModalLogic'

export type ScoutNewModal =
    | {
          kind: 'chat'
          prompt: string
          /** The form this chat came from. Reopening it with the same values keys the same draft. */
          formInitialValues?: ScoutCreateInitialValues
      }
    | { kind: 'form'; initialValues: ScoutCreateInitialValues; descriptionOverride?: string }

export interface OpenScoutNewModal {
    /** The surface whose "New scout" button opened the modal. */
    surface: ScoutSurface
    modal: ScoutNewModal
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scoutNewModalLogicValues {
    openModal: OpenScoutNewModal | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scoutNewModalLogicActions {
    setOpenModal: (openModal: OpenScoutNewModal) => { openModal: OpenScoutNewModal }
    closeModal: () => { value: true }
}

export type scoutNewModalLogicType = MakeLogicType<scoutNewModalLogicValues, scoutNewModalLogicActions>

/**
 * Which "New scout" modal is open. It lives outside the button, so a host that stays mounted keeps
 * the modal open when the button unmounts. The inbox header drops its actions while the onboarding
 * verdict settles, so state inside the button would close the modal while the person types.
 */
export const scoutNewModalLogic = kea<scoutNewModalLogicType>([
    path(['scenes', 'inbox', 'logics', 'scoutNewModalLogic']),

    actions({
        setOpenModal: (openModal: OpenScoutNewModal) => ({ openModal }),
        closeModal: true,
    }),

    reducers({
        openModal: [
            null as OpenScoutNewModal | null,
            {
                setOpenModal: (_, { openModal }) => openModal,
                closeModal: () => null,
            },
        ],
    }),
])
