export const reportRoutingLogic = kea<reportRoutingLogicType>([
    props({} as ReportRoutingLogicProps),
    key(({ projectId, reportId }) => `${projectId}:${reportId}`),
    path((key) => ['products', 'signals', 'reportRoutingLogic', key]),
    connect((props: ReportRoutingLogicProps) => ({
        actions: [
            inboxReportDetailLogic({ reportId: props.reportId }),
            ['loadReportArtefacts'],
            inboxRoutingLogic({ projectId: props.projectId }),
            ['routingChanged'],
        ],
    })),
    actions({
        setDomainId: (domainId: string | null) => ({ domainId }),
        setTeamId: (teamId: string | null) => ({ teamId }),
    }),
    loaders(({ props, values }) => ({
        state: [
            null as SignalReportRoutingStateApi | null,
            {
                loadState: async () => signalsReportsRoutingList(props.projectId, props.reportId),
                notMe: async () => signalsReportsRoutingNotMeCreate(props.projectId, props.reportId),
                restore: async () => signalsReportsRoutingRestoreCreate(props.projectId, props.reportId),
                saveRouting: async () =>
                    signalsReportsRoutingCreate(props.projectId, props.reportId, {
                        domain_id: values.domainId,
                        owning_role_id: values.teamId,
                    }),
            },
        ],
    })),
    reducers({
        domainId: [
            null as string | null,
            {
                setDomainId: (_, { domainId }) => domainId,
                loadStateSuccess: (_, { state }) => state.routing?.domain?.id ?? null,
                saveRoutingSuccess: (_, { state }) => state.routing?.domain?.id ?? null,
            },
        ],
        teamId: [
            null as string | null,
            {
                setTeamId: (_, { teamId }) => teamId,
                loadStateSuccess: (_, { state }) => state.routing?.owning_role_id ?? null,
                saveRoutingSuccess: (_, { state }) => state.routing?.owning_role_id ?? null,
            },
        ],
        error: [
            null as string | null,
            {
                loadState: () => null,
                notMe: () => null,
                restore: () => null,
                saveRouting: () => null,
                loadStateFailure: () => 'Could not load routing. Try again.',
                notMeFailure: () => 'Could not remove your suggestion. Try again.',
                restoreFailure: () => 'Could not restore your suggestion. Check your domain rules and try again.',
                saveRoutingFailure: () => 'Could not save routing. Choose a current domain and team, then try again.',
            },
        ],
    }),
    listeners(({ actions, props }) => ({
        setDomainId: ({ domainId }) => {
            const domain = inboxRoutingLogic({ projectId: props.projectId }).values.catalogue?.domains.find(
                (domain) => domain.id === domainId
            )
            actions.setTeamId(domain?.owning_role_id ?? null)
        },
        notMeSuccess: () => {
            actions.routingChanged()
            actions.loadReportArtefacts()
        },
        restoreSuccess: () => {
            actions.routingChanged()
            actions.loadReportArtefacts()
        },
        saveRoutingSuccess: () => {
            actions.routingChanged()
            actions.loadReportArtefacts()
        },
    })),
    afterMount(({ actions }) => actions.loadState()),
])
