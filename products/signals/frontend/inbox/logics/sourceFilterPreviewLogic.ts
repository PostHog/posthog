export interface SourceFilterPreviewInput {
    expression: string
    /** The unsaved record allowlist: null for the saved one, an empty list for every team. */
    scopeIds: string[] | null
}

export interface SourceFilterPreviewLogicProps {
    sourceConfig: SignalSourceConfig
    catalog: SourceFilterCatalogApi
}

const PREVIEW_VALIDATE_DELAY_MS = 300
/** Pause from the last change to the preview request, not counting the validation round trip. */
const PREVIEW_QUERY_DELAY_MS = 800
/** Mirrors `PREVIEW_LOOKBACK_DAYS` on the backend, for an invalid result before any preview has answered. */
const PREVIEW_LOOKBACK_DAYS = 7
/** Wait before retrying a throttled request whose response has no usable `Retry-After` header. */
const THROTTLED_RETRY_FALLBACK_MS = 10_000
const PREVIEW_TIMER_KEY = 'previewTimer'

/**
 * The allowlist the editor's form values would save. A selection with no teams yet falls back to the
 * saved allowlist, because an empty list would preview every team.
 */
export function previewScopeIds(
    sourceConfig: SignalSourceConfig,
    values: Pick<SourceFilterFormValues, 'teamScope' | 'teamIds'>
): string[] | null {
    if (!sourceReadsLinearTeams(sourceConfig)) {
        return null
    }
    if (values.teamScope === 'all') {
        return []
    }
    return values.teamIds.length > 0 ? values.teamIds : null
}

function samePreviewInput(a: SourceFilterPreviewInput, b: SourceFilterPreviewInput): boolean {
    if (a.expression !== b.expression) {
        return false
    }
    if (a.scopeIds === null || b.scopeIds === null) {
        return a.scopeIds === b.scopeIds
    }
    const otherIds = b.scopeIds
    return a.scopeIds.length === otherIds.length && a.scopeIds.every((id, index) => id === otherIds[index])
}

function isThrottled(error: unknown): error is ApiError {
    return error instanceof ApiError && error.status === 429
}

/** `ApiError.retryAfterSeconds` reads the header only on a 503, so a 429 reads it here. */
function throttledRetryDelayMs(error: ApiError): number {
    const retryAfter = error.headers?.get('Retry-After')
    return retryAfter && /^\d+$/.test(retryAfter) ? Number(retryAfter) * 1000 : THROTTLED_RETRY_FALLBACK_MS
}

function invalidResult(
    validation: SourceFilterValidateResponseApi,
    lastPreview: SourceFilterPreviewResponseApi | null
): SourceFilterPreviewResponseApi {
    return {
        status: 'invalid_expression',
        error: validation.error,
        error_code: validation.error_code,
        error_start: validation.error_start,
        error_end: validation.error_end,
        catalog_version: validation.catalog_version,
        lookback_days: lastPreview?.lookback_days ?? PREVIEW_LOOKBACK_DAYS,
        total_count: 0,
        passing_count: 0,
        excluded_count: 0,
        malformed_count: 0,
        passing: [],
        excluded: [],
    }
}

