export const sourceFilterPreviewLogic: LogicWrapper<sourceFilterPreviewLogicType> = kea<sourceFilterPreviewLogicType>([
    path(['products', 'signals', 'inbox', 'logics', 'sourceFilterPreviewLogic']),
    props({} as SourceFilterPreviewLogicProps),
    key((logicProps) => logicProps.sourceConfig.id),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        setPreviewInput: (input: SourceFilterPreviewInput) => ({ input }),
        retryPreview: true,
        previewInputChanged: (input: SourceFilterPreviewInput) => ({ input }),
        validatePreviewInput: (immediate: boolean) => ({ immediate }),
        loadPreview: true,
        validationLoaded: (validation: SourceFilterValidateResponseApi) => ({ validation }),
        previewLoaded: (preview: SourceFilterPreviewResponseApi) => ({ preview }),
        previewRequestFailed: (error: SourceFilterPreviewRequestError) => ({ error }),
    }),
    reducers({
        previewInput: [
            null as SourceFilterPreviewInput | null,
            {
                previewInputChanged: (_, { input }) => input,
                // A fresh object marks every request still in flight for the old one as stale.
                retryPreview: (state) => (state ? { ...state } : state),
            },
        ],
        validation: [
            null as SourceFilterValidateResponseApi | null,
            { validationLoaded: (_, { validation }) => validation },
        ],
        lastPreview: [null as SourceFilterPreviewResponseApi | null, { previewLoaded: (_, { preview }) => preview }],
        previewLoading: [
            false,
            {
                previewInputChanged: () => true,
                validatePreviewInput: () => true,
                validationLoaded: (_, { validation }) => validation.valid,
                previewLoaded: () => false,
                previewRequestFailed: () => false,
            },
        ],
        previewRequestError: [
            null as SourceFilterPreviewRequestError | null,
            {
                previewRequestFailed: (_, { error }) => error,
                validationLoaded: () => null,
                previewLoaded: () => null,
            },
        ],
    }),
    selectors({
        previewResult: [
            (s) => [s.validation, s.lastPreview],
            (
                validation: SourceFilterValidateResponseApi | null,
                lastPreview: SourceFilterPreviewResponseApi | null
            ): SourceFilterPreviewResponseApi | null =>
                validation && !validation.valid ? invalidResult(validation, lastPreview) : lastPreview,
        ],
    }),
    listeners(({ actions, values, props: logicProps, cache }) => {
        const schedule = (ms: number, run: () => void): void => {
            // The plugin runs setup again when a hidden tab shows, so each run waits only for what is left.
            const deadline = Date.now() + ms
            cache.disposables.add(() => {
                const timerId = setTimeout(
                    () => {
                        cache.disposables.dispose(PREVIEW_TIMER_KEY)
                        run()
                    },
                    Math.max(0, deadline - Date.now())
                )
                return () => clearTimeout(timerId)
            }, PREVIEW_TIMER_KEY)
        }
        // `breakpoint()` throws once the logic unmounts, so nothing dispatches on a torn-down logic.
        const isLatest = (input: SourceFilterPreviewInput, breakpoint: () => void): boolean => {
            breakpoint()
            return values.previewInput === input
        }
        const requestBase = (input: SourceFilterPreviewInput): SourceFilterExpressionRequestApi => ({
            source_product: logicProps.sourceConfig.source_product,
            source_type: logicProps.sourceConfig.source_type,
            expression: input.expression,
        })

        const captureShown = (requestError: SourceFilterPreviewRequestError | null): void => {
            captureSignalSourceFilterPreviewShown({
                sourceProduct: logicProps.sourceConfig.source_product,
                sourceType: logicProps.sourceConfig.source_type,
                // The panel shows only the error notice, so an older result does not describe what the person sees.
                result: requestError ? null : values.previewResult,
                requestError,
            })
        }

        const requestFailed = (error: unknown): void => {
            if (isThrottled(error)) {
                actions.previewRequestFailed('throttled')
                schedule(throttledRetryDelayMs(error), () => actions.retryPreview())
            } else {
                actions.previewRequestFailed('failed')
            }
        }

        return {
            setPreviewInput: ({ input }) => {
                if (!values.previewInput || !samePreviewInput(values.previewInput, input)) {
                    actions.previewInputChanged(input)
                }
            },
            previewInputChanged: () => {
                schedule(PREVIEW_VALIDATE_DELAY_MS, () => actions.validatePreviewInput(false))
            },
            validationLoaded: ({ validation }) => {
                if (!validation.valid) {
                    captureShown(null)
                }
            },
            previewLoaded: () => captureShown(null),
            previewRequestFailed: ({ error }) => captureShown(error),
            retryPreview: () => {
                if (values.previewInput) {
                    cache.disposables.dispose(PREVIEW_TIMER_KEY)
                    actions.validatePreviewInput(true)
                }
            },
            validatePreviewInput: async ({ immediate }, breakpoint) => {
                const input = values.previewInput
                if (!input) {
                    return
                }
                let validation: SourceFilterValidateResponseApi
                try {
                    validation = await signalsSourceConfigsFilterValidateCreate(
                        String(values.currentTeamId),
                        requestBase(input)
                    )
                } catch (error) {
                    if (isLatest(input, breakpoint)) {
                        requestFailed(error)
                    }
                    return
                }
                if (!isLatest(input, breakpoint)) {
                    return
                }
                actions.validationLoaded(validation)
                if (!validation.valid) {
                    return
                }
                if (immediate) {
                    actions.loadPreview()
                } else {
                    schedule(PREVIEW_QUERY_DELAY_MS - PREVIEW_VALIDATE_DELAY_MS, () => actions.loadPreview())
                }
            },
            loadPreview: async (_, breakpoint) => {
                const input = values.previewInput
                if (!input) {
                    return
                }
                let preview: SourceFilterPreviewResponseApi
                try {
                    preview = await signalsSourceConfigsFilterPreviewCreate(String(values.currentTeamId), {
                        ...requestBase(input),
                        ...(input.scopeIds !== null ? { scope_ids: input.scopeIds } : {}),
                    })
                } catch (error) {
                    if (isLatest(input, breakpoint)) {
                        requestFailed(error)
                    }
                    return
                }
                if (isLatest(input, breakpoint)) {
                    actions.previewLoaded(preview)
                }
            },
        }
    }),
])
