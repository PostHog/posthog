/**
 * The scout page's actions: what each control may do and what it runs. The title buttons in both navigations, the
 * scene menu bar, and the dialogs they open all read this one logic.
 */
export const scoutDetailActionsLogic = kea<scoutDetailActionsLogicType>([
    props({} as ScoutDetailActionsLogicProps),
    key((props) => props.skillName),
    path((key) => ['products', 'signals', 'frontend', 'inbox', 'logics', 'scoutDetailActionsLogic', key]),
    connect((props: ScoutDetailActionsLogicProps) => ({
        values: [
            scoutFleetLogic,
            ['scoutConfigs', 'manualRunScoutIds', 'publishingScoutIds', 'updatingScoutIds', 'runNotePopoverConfigId'],
            scoutNotesLogic({ skillName: props.skillName }),
            ['savingNote'],
            featureFlagLogic,
            ['featureFlags'],
            userLogic,
            ['user'],
            teamLogic,
            ['currentProjectId', 'currentTeamId'],
        ],
        actions: [
            scoutFleetLogic,
            ['runScoutNow', 'updateScoutConfig', 'publishScoutToCommunity', 'setRunNotePopoverConfigId'],
        ],
    })),
    actions({
        runNow: true,
        leaveNote: true,
        setEnabled: (enabled: boolean) => ({ enabled }),
        publish: true,
        setRunNoteOpen: (open: boolean) => ({ open }),
        openDialog: (dialog: ScoutDialog) => ({ dialog }),
        closeDialog: true,
        skillOpened: true,
    }),
    reducers({
        dialog: [
            null as ScoutDialog | null,
            {
                openDialog: (_, { dialog }) => dialog,
                closeDialog: () => null,
            },
        ],
    }),
    selectors({
        config: [
            (s, p) => [s.scoutConfigs, p.skillName],
            (scoutConfigs: SignalScoutConfig[] | null, skillName: string): SignalScoutConfig | null =>
                scoutConfigs?.find((config) => config.skill_name === skillName) ?? null,
        ],
        running: [
            (s) => [s.config, s.manualRunScoutIds],
            (config: SignalScoutConfig | null, manualRunScoutIds: string[]): boolean =>
                !!config && manualRunScoutIds.includes(config.id),
        ],
        publishing: [
            (s) => [s.config, s.publishingScoutIds],
            (config: SignalScoutConfig | null, publishingScoutIds: string[]): boolean =>
                !!config && publishingScoutIds.includes(config.id),
        ],
        updating: [
            (s) => [s.config, s.updatingScoutIds],
            (config: SignalScoutConfig | null, updatingScoutIds: string[]): boolean =>
                !!config && updatingScoutIds.includes(config.id),
        ],
        runNoteOpen: [
            (s) => [s.config, s.runNotePopoverConfigId],
            (config: SignalScoutConfig | null, runNotePopoverConfigId: string | null): boolean =>
                !!config && runNotePopoverConfigId === config.id,
        ],
        canPublish: [
            (s) => [s.config, s.featureFlags],
            (config: SignalScoutConfig | null, featureFlags: FeatureFlagsSet): boolean =>
                !!config &&
                !!featureFlags[FEATURE_FLAGS.LLM_ANALYTICS_COMMUNITY_SKILLS] &&
                config.scout_origin !== 'canonical',
        ],
        // Ownership alone lets any project member through, but the publish endpoint needs skill editor
        // access — without this the owner fills in the whole dialog and the submit returns 403.
        publishDisabledReason: [
            (s) => [s.config, s.user, s.publishing],
            (config: SignalScoutConfig | null, user: UserType | null, publishing: boolean): string | undefined => {
                const owners = config?.owners ?? []
                if (publishing) {
                    return 'Opening a pull request'
                }
                if (owners.length === 0) {
                    return 'Add an owner before publishing to the community'
                }
                if (!user || !owners.some((owner) => owner.uuid === user.uuid)) {
                    return "Only the scout's owners can publish it"
                }
                return skillEditorDisabledReason()
            },
        ],
        canEditRubrics: [
            (s) => [s.currentTeamId, s.user],
            (currentTeamId: number | null, user: UserType | null): boolean => canEditScoutRubrics(currentTeamId, user),
        ],
        // A run note reaches the agent verbatim, so the backend asks for the same skill editor access as a scout note.
        runNoteDisabledReason: [(s) => [s.user], (): string | undefined => skillEditorDisabledReason()],
        noteDisabledReason: [
            (s) => [s.savingNote],
            (savingNote: boolean): string | undefined =>
                scoutNoteWriteDisabledReason() ?? (savingNote ? 'Saving the note' : undefined),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        runNow: () => {
            if (values.config) {
                actions.runScoutNow(values.config.id)
            }
        },
        leaveNote: () => openLeaveScoutNoteDialog(props.skillName),
        setEnabled: ({ enabled }) => {
            if (values.config) {
                actions.updateScoutConfig(values.config.id, { enabled })
            }
        },
        setRunNoteOpen: ({ open }) =>
            actions.setRunNotePopoverConfigId(open && values.config ? values.config.id : null),
        publish: () => {
            const config = values.config
            if (!config) {
                return
            }
            openPublishToCommunityDialog({
                skillName: config.skill_name,
                // The scout page doesn't load the skills logic that resolves a
                // linked GitHub identity, so the handle field starts empty here.
                githubLogin: null,
                isScout: true,
                // A scout's skill is seeded on the canonical parent team, so both the consent preview and the
                // publish itself read that team rather than the child environment the page may be scoped to.
                teamId: typeof values.currentProjectId === 'number' ? values.currentProjectId : undefined,
                onPublish: (_skillName, options) => actions.publishScoutToCommunity(config.id, options),
            })
        },
        openDialog: ({ dialog }) => {
            if (dialog === 'settings') {
                captureScoutAction({ actionType: 'open_settings', surface: 'scout_detail', skillName: props.skillName })
            }
        },
        skillOpened: () => {
            captureScoutAction({
                actionType: 'open_skill_in_posthog',
                surface: 'scout_detail',
                skillName: props.skillName,
            })
        },
    })),
])
