/** Bounded by the run serializer; mirrored here so the counter can say so before a failed request. */
export const RUN_NOTE_MAX_CHARS = 1000

export function runNoteSubmitDisabledReason(running: boolean, note: string): string | undefined {
    return running ? 'Starting a run' : !note.trim() ? 'Write a note, or use Run now for a plain run' : undefined
}

/** Rubrics are a staff tool on the PostHog project only. */
export function canEditScoutRubrics(currentTeamId: number | null, user: UserType | null): boolean {
    return currentTeamId === 2 && !!user?.is_staff
}

function skillEditorDisabledReason(): string | undefined {
    return getAccessControlDisabledReason(AccessControlResourceType.LlmSkill, AccessControlLevel.Editor) ?? undefined
}

