/** Mirrors `MAX_SLACK_SCOUT_CHANNELS` in `slack_channel_scouts.py`. */
export const MAX_SLACK_SCOUT_CHANNELS = 20

export interface SlackChannelScoutFormValues {
    display_name: string
    source_id: string | null
    channel_ids: string[]
    steer: string
    /** Null runs the scout on the default daily interval. */
    run_cron_schedule: string | null
    /** False is a dry run: the scout runs and logs, but files nothing in the inbox. */
    emit: boolean
}

export const SLACK_SCOUT_SCHEDULE_OPTIONS: { value: string | null; label: string }[] = [
    { value: null, label: 'Once a day' },
    { value: '0 9 * * 1-5', label: 'Weekdays at 9:00' },
    { value: '0 9,17 * * *', label: 'Twice a day, at 9:00 and 17:00' },
    { value: '0 9 * * 1', label: 'Mondays at 9:00' },
]

function formDefaults(sources: SlackScoutChannelSourceApi[] | null): SlackChannelScoutFormValues {
    return {
        display_name: '',
        source_id: sources?.[0]?.id ?? null,
        channel_ids: [],
        steer: '',
        run_cron_schedule: null,
        emit: true,
    }
}

