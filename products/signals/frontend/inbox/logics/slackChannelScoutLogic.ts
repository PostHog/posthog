export const slackChannelScoutLogic = kea<slackChannelScoutLogicType>([
    path(['products', 'signals', 'inbox', 'logics', 'slackChannelScoutLogic']),
    actions({
        openSlackScoutModal: true,
        closeSlackScoutModal: true,
    }),
    reducers({
        isSlackScoutModalOpen: [
            false,
            {
                openSlackScoutModal: () => true,
                closeSlackScoutModal: () => false,
            },
        ],
    }),
    loaders({
        // Null until the first load answers, so "no Slack source" is never read from a pending request.
        channelSources: [
            null as SlackScoutChannelSourceApi[] | null,
            {
                loadChannelSources: async () =>
                    (await signalsSlackChannelScoutsChannelsRetrieve(String(ApiConfig.getCurrentProjectId()))).sources,
            },
        ],
        slackScouts: [
            null as SignalScoutConfigApi[] | null,
            {
                loadSlackScouts: async () =>
                    await signalsScoutConfigList(String(ApiConfig.getCurrentProjectId()), {
                        source_product: 'slack',
                    }),
            },
        ],
    }),
    forms(({ actions }) => ({
        slackScout: {
            defaults: formDefaults(null),
            errors: ({ display_name, source_id, channel_ids }: SlackChannelScoutFormValues) => ({
                display_name: !display_name.trim() ? 'Give the scout a name' : undefined,
                source_id: !source_id ? 'Pick a Slack workspace' : undefined,
                // kea-forms types an array field's errors per item, but the field shows one message for the whole list.
                channel_ids: (channel_ids.length === 0
                    ? 'Pick at least one channel'
                    : channel_ids.length > MAX_SLACK_SCOUT_CHANNELS
                      ? `Pick ${MAX_SLACK_SCOUT_CHANNELS} channels or fewer`
                      : undefined) as unknown as string[] | undefined,
            }),
            submit: async (formValues: SlackChannelScoutFormValues) => {
                let skillName: string
                try {
                    const response = await signalsSlackChannelScoutsCreate(String(ApiConfig.getCurrentProjectId()), {
                        display_name: formValues.display_name.trim(),
                        source_id: formValues.source_id as string,
                        channel_ids: formValues.channel_ids,
                        steer: formValues.steer.trim(),
                        run_cron_schedule: formValues.run_cron_schedule,
                        emit: formValues.emit,
                    })
                    skillName = response.skill_name
                } catch (error) {
                    const apiError = error instanceof ApiError ? error : null
                    captureSlackChannelScoutCreateFailed({
                        channelCount: formValues.channel_ids.length,
                        status: apiError?.status ?? null,
                    })
                    lemonToast.error(apiError?.detail ?? "Couldn't create the scout. Please try again.")
                    throw error
                }
                lemonToast.success(`${formValues.display_name.trim()} is set up`, {
                    button: { label: 'Open scout', action: () => router.actions.push(urls.inboxScout(skillName)) },
                })
                actions.closeSlackScoutModal()
                actions.loadSlackScouts()
            },
        },
    })),
    selectors({
        selectedSourceChannels: [
            (s) => [s.channelSources, s.slackScout],
            (sources: SlackScoutChannelSourceApi[] | null, form: SlackChannelScoutFormValues): SlackScoutChannelApi[] =>
                sources?.find((source) => source.id === form.source_id)?.channels ?? [],
        ],
        channelOptions: [
            (s) => [s.selectedSourceChannels],
            (channels: SlackScoutChannelApi[]): { key: string; label: string }[] =>
                channels
                    .filter((channel) => channel.table_name !== null)
                    .map((channel) => ({ key: channel.id, label: `#${channel.name}` })),
        ],
        unsyncedChannelCount: [
            (s) => [s.selectedSourceChannels],
            (channels: SlackScoutChannelApi[]): number =>
                channels.filter((channel) => channel.table_name === null).length,
        ],
    }),
    listeners(({ actions, values }) => ({
        openSlackScoutModal: () => {
            actions.resetSlackScout(formDefaults(values.channelSources))
            captureSlackChannelScoutFormOpened({
                channelCount: values.channelSources?.reduce((count, source) => count + source.channels.length, 0) ?? 0,
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadChannelSources()
        actions.loadSlackScouts()
    }),
])
