async function allPages<T>(load: (offset: number) => Promise<{ results: T[]; next?: string | null }>): Promise<T[]> {
    const results: T[] = []
    for (;;) {
        const page = await load(results.length)
        results.push(...page.results)
        if (!page.next || page.results.length === 0) {
            return results
        }
    }
}

