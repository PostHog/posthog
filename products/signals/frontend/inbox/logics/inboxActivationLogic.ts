export type inboxActivationLogicType = MakeLogicType<
    inboxActivationLogicValues,
    inboxActivationLogicActions,
    Record<string, any>,
    inboxActivationLogicMeta
>

export const inboxActivationLogic = kea<inboxActivationLogicType>([
    path(['products', 'signals', 'inbox', 'inboxActivationLogic']),
    connect({
        values: [
            inboxSetupLogic,
            ['savedState', 'currentTeamId'],
            signalSourcesLogic,
            ['sourceConfigs', 'hasEmittingScanner'],
            scoutFleetLogic,
            ['scoutConfigs'],
            scoutSuggestionsLogic,
            ['suggestionSet', 'suggestionSetLoading', 'suggestions'],
        ],
        actions: [
            inboxSetupLogic,
            ['loadSetup', 'setSavedState'],
            signalSourcesLogic,
            ['loadSourceConfigs', 'loadVisionScanners'],
            scoutFleetLogic,
            ['loadScoutConfigs'],
            scoutSuggestionsLogic,
            ['loadSuggestions'],
        ],
    }),
    actions({ refresh: true, setPollingExpired: true }),
    reducers({ pollingExpired: [false, { setPollingExpired: () => true }] }),
    selectors({
        sourceNames: [
            (s) => [s.sourceConfigs, s.hasEmittingScanner],
            (configs: SignalSourceConfig[] | null, replay: boolean | null): string[] =>
                AGENT_ROSTER_GROUPS.flatMap((group) => group.agents)
                    .filter((source) =>
                        source.source === 'replay_vision'
                            ? replay
                            : configs?.some(
                                  (config) => config.source_product === source.sourceProduct && config.enabled
                              )
                    )
                    .map((source) => source.label),
        ],
        generalScout: [
            (s) => [s.scoutConfigs],
            (configs: SignalScoutConfig[] | null): SignalScoutConfig | null =>
                configs?.find((config) => config.skill_name === 'signals-scout-general') ?? null,
        ],
        recommendationsReady: [
            (s) => [s.suggestionSet, s.savedState],
            (set: ScoutSuggestionSetApi | null, state: InboxOnboardingStateApi | null): boolean =>
                !!set?.generated_at &&
                !!state?.completed_at &&
                new Date(set.generated_at) >= new Date(state.completed_at),
        ],
    }),
    listeners(({ actions, values }) => ({
        refresh: () => {
            actions.loadSetup()
            if (!values.suggestionSetLoading) {
                actions.loadSuggestions()
            }
        },
    })),
    afterMount(({ actions, values, cache }) => {
        actions.loadSourceConfigs()
        actions.loadVisionScanners()
        actions.loadScoutConfigs()
        actions.refresh()
        cache.disposables.add(() => {
            const interval = setInterval(() => {
                const completedAt = values.savedState?.completed_at
                if (values.recommendationsReady) {
                    cache.disposables.dispose('activation')
                    return
                }
                if (completedAt && Date.now() - new Date(completedAt).valueOf() > 15 * 60_000) {
                    actions.setPollingExpired()
                    cache.disposables.dispose('activation')
                    return
                }
                actions.refresh()
            }, 10_000)
            return () => clearInterval(interval)
        }, 'activation')
    }),
])
