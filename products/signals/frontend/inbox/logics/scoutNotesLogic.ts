import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'

import {
    signalsScoutNotesCreate,
    signalsScoutNotesDestroy,
    signalsScoutNotesList,
} from 'products/signals/frontend/generated/api'
import type { ScoutNoteApi } from 'products/signals/frontend/generated/api.schemas'

import { captureScoutAction } from '../inboxAnalytics'

export interface ScoutNotesLogicProps {
    /** The scout these notes steer, or '' for the fleet-wide view. */
    skillName: string
}

/**
 * Where a note came from, in the words a reader needs. A note someone typed is a directive; one
 * derived from inbox activity is evidence about a particular report, and reads very differently —
 * so the origin is shown rather than flattened into "a note".
 */
export const SCOUT_NOTE_ORIGIN_LABEL: Record<string, string> = {
    human: 'Left directly',
    report_dismissal: 'From a dismissal',
    report_discussion: 'From a discussion',
    report_feedback: 'From a rating',
}

export function scoutNoteOriginLabel(origin: string): string {
    return SCOUT_NOTE_ORIGIN_LABEL[origin] ?? 'From the inbox'
}

/** A note left directly is the team steering the fleet; the rest are derived from inbox activity. */
export function isDirectScoutNote(note: ScoutNoteApi): boolean {
    return note.origin === 'human'
}

const NOTES_FETCH_LIMIT = 50

