const DISCOVERY_POLL_INTERVAL_MS = 4000

function discoveryErrorMessage(error: unknown): string {
    if (error instanceof ApiError) {
        return error.detail || error.message
    }
    return error instanceof Error ? error.message : 'Feature discovery could not start. Try again.'
}

