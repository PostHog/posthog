export const featureDiscoveryLogic = kea<featureDiscoveryLogicType>([
    path(['scenes', 'inbox', 'logics', 'featureDiscoveryLogic']),

    connect(() => ({
        values: [teamLogic, ['currentProjectId'], integrationsLogic, ['githubIntegrations', 'integrationsLoading']],
        actions: [featureListLogic, ['loadFeatures']],
    })),

    actions({
        openDiscoveryModal: true,
        closeDiscoveryModal: true,
        setRepository: (repository: string) => ({ repository }),
        setFocus: (focus: string) => ({ focus }),
    }),

    reducers({
        discoveryModalOpen: [
            false,
            {
                openDiscoveryModal: () => true,
                closeDiscoveryModal: () => false,
            },
        ],
        repository: [
            '',
            {
                setRepository: (_, { repository }) => repository,
                closeDiscoveryModal: () => '',
            },
        ],
        focus: [
            '',
            {
                setFocus: (_, { focus }) => focus,
                closeDiscoveryModal: () => '',
            },
        ],
    }),

    selectors({
        githubIntegration: [
            (s) => [s.githubIntegrations],
            (githubIntegrations: IntegrationType[]): IntegrationType | null => githubIntegrations[0] ?? null,
        ],
        repositoryForDiscovery: [
            (s) => [s.repository, s.githubIntegration],
            (repository: string, githubIntegration: IntegrationType | null): string | null => {
                const normalizedRepository = repository.trim()
                if (!normalizedRepository) {
                    return null
                }
                if (normalizedRepository.includes('/')) {
                    return normalizedRepository
                }
                const owner = githubIntegration?.config?.account?.name
                return typeof owner === 'string' && owner.trim() ? `${owner.trim()}/${normalizedRepository}` : null
            },
        ],
    }),

    loaders(({ values }) => ({
        discoveryRuns: [
            [] as InboxFeatureDiscoveryRunApi[],
            {
                loadDiscoveryRuns: async () => signalsFeaturesDiscoveryRunsList(String(values.currentProjectId)),
            },
        ],
        discoveryStart: [
            null as InboxFeatureDiscoveryCreatedApi | null,
            {
                startDiscovery: async () => {
                    if (!values.repository.trim()) {
                        throw new Error('Select a repository first.')
                    }
                    if (!values.repositoryForDiscovery) {
                        throw new Error('Reconnect GitHub to identify the repository owner, then try again.')
                    }
                    return signalsFeaturesDiscoverCreate(String(values.currentProjectId), {
                        repository: values.repositoryForDiscovery,
                        focus: values.focus.trim(),
                    })
                },
            },
        ],
    })),

    listeners(({ actions, cache }) => ({
        startDiscoverySuccess: () => {
            actions.closeDiscoveryModal()
            actions.loadDiscoveryRuns()
            lemonToast.success('Feature discovery started')
        },
        startDiscoveryFailure: ({ errorObject }) => {
            lemonToast.error(discoveryErrorMessage(errorObject))
        },
        loadDiscoveryRunsSuccess: ({ discoveryRuns }) => {
            const hasActiveRun = discoveryRuns.some(
                (run) => run.discovery_status === 'queued' || run.discovery_status === 'running'
            )
            if (hasActiveRun) {
                cache.disposables.add(() => {
                    const interval = setInterval(actions.loadDiscoveryRuns, DISCOVERY_POLL_INTERVAL_MS)
                    return () => clearInterval(interval)
                }, 'featureDiscoveryPoll')
            } else {
                cache.disposables.dispose('featureDiscoveryPoll')
            }
            if (discoveryRuns.some((run) => run.discovery_status === 'completed')) {
                actions.loadFeatures()
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadDiscoveryRuns()
    }),
])
