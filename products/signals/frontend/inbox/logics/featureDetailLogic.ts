export type FeatureDetailSubTab = 'status' | 'planning' | 'owner' | 'feed'

/** How often a feature refreshes while its planning agent is active. */
const PLANNING_POLL_INTERVAL_MS = 2000

function featureSubTabFromSearchParams(): FeatureDetailSubTab {
    const requestedTab = router.values.searchParams.feature_tab
    return requestedTab === 'planning' || requestedTab === 'owner' || requestedTab === 'feed' ? requestedTab : 'status'
}

/** Must mirror `owner_scout_skill_name` in the backend feature service. */
export function ownerScoutSkillName(reportId: string): string {
    return `signals-scout-feature-${reportId.split('-')[0]}`
}

/** The report fields editable in place on the feature Status tab. */
export type FeatureEditableField = 'title' | 'summary'

export interface FeatureDetailLogicProps {
    reportId: string
    report: SignalReport
}

function featureDetailErrorMessage(error: unknown, fallback: string): string {
    if (error instanceof ApiError) {
        return error.detail || error.message || fallback
    }
    return error instanceof Error ? error.message : fallback
}

function missingPlanningFields(error: unknown): string[] | undefined {
    if (!(error instanceof ApiError) || !error.data || typeof error.data !== 'object') {
        return undefined
    }
    const missing = (error.data as { missing?: unknown }).missing
    return Array.isArray(missing) && missing.every((field): field is string => typeof field === 'string')
        ? missing
        : undefined
}

