/**
 * Feature detail view state: the active sub-tab, the click-to-edit surfaces for
 * the report's title/summary, and answering question artefacts. Artefact data comes from the
 * connected `inboxReportDetailLogic` (same key), so the feature view shares its loading and polling
 * with the rest of the inbox detail machinery.
 */
export const featureDetailLogic = kea<featureDetailLogicType>([
    path((key) => ['scenes', 'inbox', 'logics', 'featureDetailLogic', key]),
    props({} as FeatureDetailLogicProps),
    key((props) => props.reportId),

    connect((props: FeatureDetailLogicProps) => ({
        values: [
            inboxReportDetailLogic(props),
            ['reportArtefacts', 'reportTasks', 'primaryTask'],
            teamLogic,
            ['currentProjectId'],
        ],
        actions: [
            inboxReportDetailLogic(props),
            ['loadReportArtefacts', 'loadReportTasksSuccess'],
            inboxSceneLogic,
            ['seedSelectedReport', 'loadSelectedReport'],
            teamLogic,
            ['loadCurrentTeamSuccess'],
        ],
    })),

    loaders(({ props, values }) => ({
        // The deterministic skill name is the ownership link between the feature and its scout.
        ownerScoutConfig: [
            null as SignalScoutConfigApi | null,
            {
                loadOwnerScoutConfig: async () => {
                    const configs = await signalsScoutConfigList(String(values.currentProjectId))
                    return configs.find((c) => c.skill_name === ownerScoutSkillName(props.reportId)) ?? null
                },
            },
        ],
    })),

    actions({
        setActiveSubTab: (subTab: FeatureDetailSubTab) => ({ subTab }),
        // Report title/summary click-to-edit.
        startEditingField: (field: FeatureEditableField, initial: string) => ({ field, initial }),
        setFieldDraft: (draft: string) => ({ draft }),
        cancelEditingField: true,
        saveField: true,
        setFieldSaving: (saving: boolean) => ({ saving }),
        // Question answering.
        startAnswering: (artefactId: string) => ({ artefactId }),
        setAnswerDraft: (draft: string) => ({ draft }),
        cancelAnswering: true,
        saveAnswer: (answer?: string) => ({ answer }),
        setAnswerSaving: (saving: boolean) => ({ saving }),
        // User feedback: `question` artefacts authored by the user (attribution = user id), which
        // the owner scout acts on and answers on its next run.
        setFeedbackDraft: (draft: string) => ({ draft }),
        saveFeedback: true,
        saveFeedbackSuccess: true,
        setFeedbackSaving: (saving: boolean) => ({ saving }),
        // Complete initial planning and activate the owner scout.
        finishPlanning: true,
        setFinishingPlanning: (finishingPlanning: boolean) => ({ finishingPlanning }),
        startPlanningSession: true,
        setStartingPlanningSession: (starting: boolean) => ({ starting }),
        // Manually start an implementation pass (shown when the feature has none yet).
        startImplementation: true,
        setStartingImplementation: (starting: boolean) => ({ starting }),
    }),

    reducers({
        activeSubTab: [
            'status' as FeatureDetailSubTab,
            {
                setActiveSubTab: (_, { subTab }) => subTab,
            },
        ],
        editingField: [
            null as FeatureEditableField | null,
            {
                startEditingField: (_, { field }) => field,
                cancelEditingField: () => null,
            },
        ],
        fieldDraft: [
            '',
            {
                startEditingField: (_, { initial }) => initial,
                setFieldDraft: (_, { draft }) => draft,
                cancelEditingField: () => '',
            },
        ],
        fieldSaving: [
            false,
            {
                setFieldSaving: (_, { saving }) => saving,
            },
        ],
        answeringQuestionId: [
            null as string | null,
            {
                startAnswering: (_, { artefactId }) => artefactId,
                cancelAnswering: () => null,
            },
        ],
        answerDraft: [
            '',
            {
                startAnswering: () => '',
                setAnswerDraft: (_, { draft }) => draft,
                cancelAnswering: () => '',
            },
        ],
        answerSaving: [
            false,
            {
                setAnswerSaving: (_, { saving }) => saving,
            },
        ],
        feedbackDraft: [
            '',
            {
                setFeedbackDraft: (_, { draft }) => draft,
                saveFeedbackSuccess: () => '',
            },
        ],
        feedbackSaving: [
            false,
            {
                setFeedbackSaving: (_, { saving }) => saving,
            },
        ],
        finishingPlanning: [
            false,
            {
                setFinishingPlanning: (_, { finishingPlanning }) => finishingPlanning,
            },
        ],
        startingPlanningSession: [
            false,
            {
                setStartingPlanningSession: (_, { starting }) => starting,
            },
        ],
        startingImplementation: [
            false,
            {
                setStartingImplementation: (_, { starting }) => starting,
            },
        ],
    }),

    selectors({
        questionArtefacts: [
            (s) => [s.reportArtefacts],
            (reportArtefacts: SignalReportArtefact[] | null): SignalReportArtefact[] =>
                (reportArtefacts ?? []).filter((a) => a.type === 'question'),
        ],
        /**
         * A question's direction is its attribution: `created_by` set → from the user (feedback, for
         * an agent to answer); otherwise (task/system attributed) → from an agent, for the user.
         */
        openQuestions: [
            (s) => [s.questionArtefacts],
            (questionArtefacts: SignalReportArtefact[]): SignalReportArtefact[] =>
                questionArtefacts.filter((a) => !a.content?.answered && !a.created_by),
        ],
        outstandingFeedback: [
            (s) => [s.questionArtefacts],
            (questionArtefacts: SignalReportArtefact[]): SignalReportArtefact[] =>
                questionArtefacts.filter((a) => !a.content?.answered && !!a.created_by),
        ],
        answeredQuestions: [
            (s) => [s.questionArtefacts],
            (questionArtefacts: SignalReportArtefact[]): SignalReportArtefact[] =>
                questionArtefacts.filter((a) => !!a.content?.answered),
        ],
        featureStage: [
            (s) => [s.reportArtefacts],
            (reportArtefacts: SignalReportArtefact[] | null): 'staged' | 'planning' | 'managed' | null => {
                if (reportArtefacts === null) {
                    return null
                }
                const lifecycle = reportArtefacts
                    .filter((artefact) => artefact.type === 'feature_lifecycle')
                    .reduce<SignalReportArtefact | null>(
                        (latest, artefact) => (!latest || artefact.created_at > latest.created_at ? artefact : latest),
                        null
                    )
                const stage = lifecycle?.content?.feature_stage
                if (stage === 'staged' || stage === 'planning' || stage === 'managed') {
                    return stage
                }
                return reportArtefacts.some((artefact) => artefact.type === 'safety_judgment') ? 'managed' : 'planning'
            },
        ],
        isManaged: [
            (s) => [s.featureStage],
            (featureStage: 'staged' | 'planning' | 'managed' | null): boolean => featureStage === 'managed',
        ],
        isStaged: [
            (s) => [s.featureStage],
            (featureStage: 'staged' | 'planning' | 'managed' | null): boolean => featureStage === 'staged',
        ],
        planningTask: [
            (s) => [s.reportTasks],
            (reportTasks: ReportTaskEntry[] | null): ReportTaskEntry | null => {
                const planningTasks = (reportTasks ?? []).filter((entry) => entry.purpose === 'planning')
                return (
                    planningTasks.reduce<ReportTaskEntry | null>(
                        (latest, entry) =>
                            !latest || new Date(entry.startedAt) > new Date(latest.startedAt) ? entry : latest,
                        null
                    ) ?? null
                )
            },
        ],
        planningSessionActive: [
            (s) => [s.planningTask],
            (planningTask: ReportTaskEntry | null): boolean => {
                const status = planningTask?.task.latest_run?.status
                return (
                    planningTask !== null &&
                    (status === undefined ||
                        ![TaskRunStatus.COMPLETED, TaskRunStatus.FAILED, TaskRunStatus.CANCELLED].includes(status))
                )
            },
        ],
        /** Whether any implementation pass has been recorded on the feature (a signals/implementation task_run artefact). */
        hasImplementationRun: [
            (s) => [s.reportArtefacts],
            (reportArtefacts: SignalReportArtefact[] | null): boolean | null =>
                reportArtefacts === null
                    ? null
                    : reportArtefacts.some(
                          (a) =>
                              a.type === 'task_run' &&
                              a.content?.product === 'signals' &&
                              a.content?.type === 'implementation'
                      ),
        ],
        /** What still blocks Finish planning. Mirrors the backend readiness labels. */
        missingForPlanningCompletion: [
            (s) => [s.reportArtefacts, (_, props: FeatureDetailLogicProps) => props.report],
            (reportArtefacts: SignalReportArtefact[] | null, report: SignalReport): string[] => {
                const missing: string[] = []
                if (!report.title?.trim()) {
                    missing.push('title')
                }
                if (!report.summary?.trim()) {
                    missing.push('summary')
                }
                const types = new Set((reportArtefacts ?? []).map((a) => a.type))
                if (!types.has('repo_selection')) {
                    missing.push('repository selection')
                }
                if (!types.has('suggested_reviewers')) {
                    missing.push('owners')
                }
                if (!types.has('priority_judgment')) {
                    missing.push('priority')
                }
                return missing
            },
        ],
    }),

    listeners(({ actions, values, props, cache }) => ({
        setActiveSubTab: ({ subTab }) => {
            const { feature_tab: _, ...searchParams } = router.values.searchParams
            router.actions.replace(
                router.values.location.pathname,
                subTab === 'status' ? searchParams : { ...searchParams, feature_tab: subTab },
                router.values.hashParams
            )
        },
        loadCurrentTeamSuccess: () => {
            if (!values.ownerScoutConfig) {
                actions.loadOwnerScoutConfig()
            }
        },
        loadReportTasksSuccess: () => {
            if (values.planningSessionActive) {
                cache.disposables.add(() => {
                    const interval = setInterval(() => {
                        actions.loadReportArtefacts()
                        actions.loadSelectedReport({ id: props.reportId })
                        actions.loadOwnerScoutConfig()
                    }, PLANNING_POLL_INTERVAL_MS)
                    return () => clearInterval(interval)
                }, 'featurePlanningPoll')
            } else {
                cache.disposables.dispose('featurePlanningPoll')
            }
        },
        finishPlanning: async () => {
            if (values.finishingPlanning) {
                return
            }
            actions.setFinishingPlanning(true)
            try {
                await signalsFeaturesFinishPlanningCreate(String(values.currentProjectId), props.reportId)
                lemonToast.success('Planning finished')
                actions.loadReportArtefacts()
                actions.loadSelectedReport({ id: props.reportId })
                actions.loadOwnerScoutConfig()
                router.actions.push(urls.inboxReport('features', props.reportId))
            } catch (error: unknown) {
                const missing = missingPlanningFields(error)
                lemonToast.error(
                    missing?.length
                        ? `Planning still needs: ${missing.join(', ')}`
                        : featureDetailErrorMessage(error, 'Failed to finish planning')
                )
            } finally {
                actions.setFinishingPlanning(false)
            }
        },
        startPlanningSession: async () => {
            if (values.startingPlanningSession) {
                return
            }
            actions.setStartingPlanningSession(true)
            try {
                await signalsFeaturesStartPlanningCreate(String(values.currentProjectId), props.reportId)
                lemonToast.success('Planning started')
                actions.setActiveSubTab('planning')
                actions.loadReportArtefacts()
                actions.loadSelectedReport({ id: props.reportId })
                actions.loadOwnerScoutConfig()
            } catch (error: unknown) {
                lemonToast.error(featureDetailErrorMessage(error, "Couldn't start planning. Try again."))
            } finally {
                actions.setStartingPlanningSession(false)
            }
        },
        startImplementation: async () => {
            if (values.startingImplementation) {
                return
            }
            actions.setStartingImplementation(true)
            try {
                await signalsFeaturesStartImplementationCreate(String(values.currentProjectId), props.reportId)
                lemonToast.success('Implementation pass started')
                actions.loadReportArtefacts()
            } catch (error: unknown) {
                lemonToast.error(featureDetailErrorMessage(error, 'Failed to start implementation'))
            } finally {
                actions.setStartingImplementation(false)
            }
        },
        saveField: async () => {
            const field = values.editingField
            if (!field || values.fieldSaving) {
                return
            }
            const draft = values.fieldDraft.trim()
            if (!draft) {
                lemonToast.error(`The ${field} cannot be empty`)
                return
            }
            actions.setFieldSaving(true)
            try {
                const updated = await signalsReportsPartialUpdate(String(values.currentProjectId), props.reportId, {
                    [field]: draft,
                })
                // Refresh the scene's copy so the header/list reflect the edit without a reload, and the
                // artefact log so the title_change/summary_change history entry appears in the feed.
                actions.seedSelectedReport({ ...props.report, title: updated.title, summary: updated.summary })
                actions.loadReportArtefacts()
                actions.cancelEditingField()
            } catch (error: unknown) {
                lemonToast.error(featureDetailErrorMessage(error, `Failed to save ${field}`))
            } finally {
                actions.setFieldSaving(false)
            }
        },
        saveFeedback: async () => {
            if (values.feedbackSaving) {
                return
            }
            const question = values.feedbackDraft.trim()
            if (!question) {
                lemonToast.error('The feedback cannot be empty')
                return
            }
            actions.setFeedbackSaving(true)
            try {
                // Attribution (this user) is what marks the question as human→agent feedback.
                await signalsReportArtefactsCreate(String(values.currentProjectId), props.reportId, {
                    artefact_type: 'question',
                    content: { question },
                })
                actions.saveFeedbackSuccess()
                actions.loadReportArtefacts()
                lemonToast.success('Feedback added. The owner scout will answer it on its next run.')
            } catch (error: unknown) {
                lemonToast.error(featureDetailErrorMessage(error, 'Failed to add feedback'))
            } finally {
                actions.setFeedbackSaving(false)
            }
        },
        saveAnswer: async ({ answer }) => {
            const artefactId = values.answeringQuestionId
            if (!artefactId || values.answerSaving) {
                return
            }
            const submittedAnswer = (answer ?? values.answerDraft).trim()
            if (!submittedAnswer) {
                lemonToast.error('The answer cannot be empty')
                return
            }
            const artefact = values.questionArtefacts.find((a) => a.id === artefactId)
            actions.setAnswerDraft(submittedAnswer)
            actions.setAnswerSaving(true)
            try {
                await signalsReportArtefactsPartialUpdate(String(values.currentProjectId), props.reportId, artefactId, {
                    content: {
                        ...artefact?.content,
                        answer: submittedAnswer,
                        answered: true,
                    },
                })
                actions.loadReportArtefacts()
                actions.cancelAnswering()
            } catch (error: unknown) {
                lemonToast.error(featureDetailErrorMessage(error, 'Failed to save answer'))
            } finally {
                actions.setAnswerSaving(false)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.setActiveSubTab(featureSubTabFromSearchParams())
        actions.loadOwnerScoutConfig()
    }),
])
