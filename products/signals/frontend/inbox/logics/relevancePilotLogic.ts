export type relevancePilotLogicType = MakeLogicType<relevancePilotLogicValues, relevancePilotLogicActions>

export const relevancePilotLogic = kea<relevancePilotLogicType>([
    path(['products', 'signals', 'inbox', 'relevancePilotLogic']),
    connect({
        values: [teamLogic, ['currentTeamId'], inboxSceneLogic, ['selectedReportId']],
        actions: [inboxFiltersLogic, ['setScope'], inboxSceneLogic, ['setSelectedReportId']],
    }),
    actions({
        loadReports: true,
        setShowQueue: (showQueue: boolean) => ({ showQueue }),
        snooze: (report: SignalReport, snoozed: boolean) => ({ report, snoozed }),
    }),
    loaders(({ values }) => ({
        reports: [
            [] as SignalReport[],
            {
                loadReports: async (_, breakpoint) => {
                    const response = await signalsReportsList(String(values.currentTeamId), {
                        view: 'for_you',
                        limit: 5,
                    })
                    breakpoint()
                    return response.results.map(
                        (report): SignalReport => ({
                            ...report,
                            status: report.status as SignalReportStatus,
                            priority: report.priority as SignalReport['priority'],
                            actionability: report.actionability as SignalReport['actionability'],
                            source_products: report.source_products ? [...report.source_products] : undefined,
                            charts: report.charts ? [...report.charts] : undefined,
                            metrics: report.metrics ? [...report.metrics] : undefined,
                            suggested_prompts: report.suggested_prompts ? [...report.suggested_prompts] : undefined,
                        })
                    )
                },
            },
        ],
        lastSnoozed: [
            null as SignalReport | null,
            {
                snooze: async ({ report, snoozed }: { report: SignalReport; snoozed: boolean }) => {
                    await signalsReportsSnoozeCreate(String(values.currentTeamId), report.id, { snoozed })
                    captureInboxReportAction({
                        report,
                        actionType: snoozed ? 'snooze' : 'undo_snooze',
                        surface: 'shortlist',
                    })
                    return snoozed ? report : null
                },
            },
        ],
    })),
    reducers({
        failed: [false, { loadReports: () => false, loadReportsFailure: () => true }],
        showQueue: [false, { setShowQueue: (_, { showQueue }) => showQueue }],
    }),
    listeners(({ actions, cache, values }) => ({
        snoozeFailure: () => {
            lemonToast.error('Could not change your shortlist. Try again.')
        },
        snoozeSuccess: () => actions.loadReports(),
        setSelectedReportId: ({ id }) => {
            if (!id) {
                actions.loadReports()
            }
        },
        setShowQueue: ({ showQueue }) => {
            if (showQueue) {
                actions.setScope(INBOX_SCOPE_ENTIRE_PROJECT)
            } else {
                actions.loadReports()
            }
        },
        loadReportsSuccess: ({ reports }) => {
            if (values.showQueue || values.selectedReportId) {
                return
            }
            const seen = (cache.seen ??= new Set<string>())
            const fresh = reports.filter((report) => !seen.has(report.id))
            fresh.forEach((report) => seen.add(report.id))
            if (fresh.length) {
                captureInboxReportsImpressed({
                    tab: 'for_you_pilot',
                    reports: fresh,
                    ranks: fresh.map((report) => reports.indexOf(report) + 1),
                    listSize: reports.length,
                    totalCount: null,
                    hasActiveFilters: false,
                    scope: 'for-you',
                })
            }
        },
    })),
    afterMount(({ actions }) => actions.loadReports()),
])
