    selectedReportId: string | null // inboxSceneLogic
    currentTeamId: number | null // teamLogic
    failed: boolean
    lastSnoozed: SignalReport | null
    lastSnoozedLoading: boolean
    reports: SignalReport[]
    reportsLoading: boolean
    showQueue: boolean
