import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'

import { signalsReportsList, signalsReportsSnoozeCreate } from 'products/signals/frontend/generated/api'

import { captureInboxReportAction, captureInboxReportsImpressed } from '../inboxAnalytics'
import { inboxSceneLogic } from '../inboxSceneLogic'
import { SignalReport, SignalReportStatus, InboxScope, INBOX_SCOPE_ENTIRE_PROJECT } from '../types'
import { inboxFiltersLogic } from './inboxFiltersLogic'

