import { signalsVisibleCustomImagesLogic } from './signalsVisibleCustomImagesLogic'

export type SignalsCustomImageOrigin =
    | typeof SandboxCustomImagesListOriginProduct.SignalsScout
    | typeof SandboxCustomImagesListOriginProduct.SignalReport

export interface SignalsCustomImagesLogicProps {
    origin: SignalsCustomImageOrigin
}

export interface CustomImageChoice {
    value: string
    name: string
    status: { label: string; type: LemonTagType } | null
}

export const MISSING_CUSTOM_IMAGE_LABEL = 'Image no longer available'

export function customImageChoices(
    usableImages: SandboxCustomImageDTOApi[] | null,
    imagesForbidden: boolean,
    savedImageId: string | null,
    originUnsupported: boolean
): CustomImageChoice[] | null {
    if (
        imagesForbidden ||
        originUnsupported ||
        usableImages === null ||
        (usableImages.length === 0 && savedImageId === null)
    ) {
        return null
    }
    const choices: CustomImageChoice[] = usableImages.map((image) => ({
        value: image.id,
        name: image.name,
        status: image.status === 'ready' ? null : cloudImageStatus(image.status),
    }))
    if (savedImageId !== null && !usableImages.some((image) => image.id === savedImageId)) {
        choices.push({ value: savedImageId, name: MISSING_CUSTOM_IMAGE_LABEL, status: null })
    }
    return choices
}

