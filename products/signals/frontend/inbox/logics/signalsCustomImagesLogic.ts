export const signalsCustomImagesLogic = kea<signalsCustomImagesLogicType>([
    props({} as SignalsCustomImagesLogicProps),
    key((props) => props.origin),
    path((key) => ['products', 'signals', 'inbox', 'logics', 'signalsCustomImagesLogic', key]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], signalsVisibleCustomImagesLogic, ['visibleImageCount']],
    })),
    loaders(({ props, values }) => ({
        images: [
            null as SandboxCustomImageDTOApi[] | null,
            {
                loadImages: async (): Promise<SandboxCustomImageDTOApi[] | null> => {
                    if (values.currentProjectId == null) {
                        return null
                    }
                    const projectId = String(values.currentProjectId)
                    return await listAllPages((params) =>
                        sandboxCustomImagesList(projectId, { ...params, origin_product: props.origin })
                    )
                },
            },
        ],
    })),
    reducers({
        imagesForbidden: [
            false,
            {
                loadImagesSuccess: () => false,
                loadImagesFailure: (_, { errorObject }) => errorObject?.status === 403,
            },
        ],
    }),
    selectors({
        usableImages: [
            (s) => [s.images],
            (images: SandboxCustomImageDTOApi[] | null): SandboxCustomImageDTOApi[] | null =>
                images === null
                    ? null
                    : images.filter((image) => image.private === false && image.status !== 'archived'),
        ],
        originUnsupported: [
            (s) => [s.images, s.visibleImageCount],
            (images: SandboxCustomImageDTOApi[] | null, visibleImageCount: number | null): boolean =>
                images !== null && images.length === 0 && (visibleImageCount ?? 0) > 0,
        ],
    }),
    afterMount(({ actions }) => actions.loadImages()),
])
