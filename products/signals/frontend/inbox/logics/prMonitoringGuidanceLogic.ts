export const prMonitoringGuidanceLogic = kea<prMonitoringGuidanceLogicType>([
    path((key) => ['products', 'signals', 'inbox', 'prMonitoringGuidanceLogic', key]),
    props({} as PrMonitoringGuidanceLogicProps),
    key((props) => props.reportId),
    connect((props: PrMonitoringGuidanceLogicProps) => ({
        values: [
            projectLogic,
            ['currentProjectId'],
            inboxReportDetailLogic(props),
            ['report as detailReport', 'reportArtefacts', 'reportArtefactsLoading', 'reportTasks'],
        ],
        actions: [inboxReportDetailLogic(props), ['loadReportArtefacts', 'openReportTask', 'setReport']],
    })),
    actions({
        setDraftNote: (draftNote: string) => ({ draftNote }),
        submitGuidance: (prUrl: string) => ({ prUrl }),
        setSubmitting: (submitting: boolean) => ({ submitting }),
        openLatestResearchRun: true,
    }),
    reducers({
        draftNote: ['', { setDraftNote: (_, { draftNote }) => draftNote }],
        submitting: [false, { setSubmitting: (_, { submitting }) => submitting }],
    }),
    selectors({
        guidanceQuestion: [
            (s) => [s.reportArtefacts, s.detailReport],
            (reportArtefacts: SignalReportArtefact[] | null, detailReport: SignalReport | null): string | null =>
                latestPrMonitoringGuidanceNote(reportArtefacts, detailReport?.status),
        ],
        latestResearchTask: [
            (s) => [s.reportTasks],
            (reportTasks: ReportTaskEntry[] | null): ReportTaskEntry | null =>
                (reportTasks ?? [])
                    .filter((entry) => entry.purpose === 'research' && entry.task.latest_run)
                    .sort((a, b) => new Date(b.startedAt).getTime() - new Date(a.startedAt).getTime())[0] ?? null,
        ],
    }),
    listeners(({ actions, props, values }) => ({
        openLatestResearchRun: () => {
            const report = values.detailReport ?? props.report ?? null
            const latest = values.latestResearchTask
            if (report && latest?.task.latest_run) {
                actions.openReportTask(report, latest.task.id, latest.task.latest_run.id)
            }
        },
        submitGuidance: async ({ prUrl }) => {
            if (values.submitting) {
                return
            }
            const projectId = values.currentProjectId ?? teamLogic.values.currentTeamId
            if (projectId == null) {
                return
            }
            const trimmedNote = values.draftNote.trim()
            capturePRAction('submit_monitor', { has_note: Boolean(trimmedNote), from_report_detail: true })
            actions.setSubmitting(true)
            try {
                const result = await signalsMonitorPrCreate(
                    String(projectId),
                    trimmedNote ? { pr_url: prUrl, note: trimmedNote } : { pr_url: prUrl }
                )
                actions.setDraftNote('')
                pullRequestsLogic.findMounted()?.actions.loadPullRequests()
                monitoringTabLogic.findMounted()?.actions.loadReports()
                if (result.report_id !== props.reportId) {
                    const rawBack = router.values.searchParams.back
                    const backPath =
                        typeof rawBack === 'string' && rawBack.startsWith('/') && !rawBack.startsWith('//')
                            ? rawBack
                            : urls.inbox('monitoring')
                    router.actions.push(inboxReportDetailUrl(result.report_id, backPath))
                    lemonToast.info('Started monitoring this pull request on your own report.')
                    return
                }
                const current = values.detailReport ?? props.report ?? null
                if (current) {
                    actions.setReport({ ...current, status: result.status as SignalReportStatus })
                }
                const scene = inboxSceneLogic.findMounted()
                if (scene?.values.selectedReportId === props.reportId && !scene.values.selectedReportLoading) {
                    scene.actions.loadSelectedReport({ id: props.reportId })
                }
                actions.loadReportArtefacts()
            } catch (err: any) {
                lemonToast.error(
                    err?.data?.detail || err?.detail || 'Could not start monitoring for this pull request.'
                )
            } finally {
                actions.setSubmitting(false)
            }
        },
    })),
])
