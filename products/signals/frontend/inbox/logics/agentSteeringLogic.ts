export type agentSteeringLogicType = MakeLogicType<
    agentSteeringLogicValues,
    agentSteeringLogicActions,
    Record<string, any>,
    agentSteeringLogicMeta
>

export const agentSteeringLogic = kea<agentSteeringLogicType>([
    path(['products', 'signals', 'inbox', 'logics', 'agentSteeringLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        selectRole: (role: SteeringRole) => ({ role }),
        setDraft: (role: SteeringRole, instructions: string) => ({ role, instructions }),
        discardDraft: (role: SteeringRole) => ({ role }),
        submitInstructions: true,
    }),
    loaders(({ values }) => ({
        steeringConfig: {
            __default: null as SignalTeamConfigApi | null,
            loadSteeringConfig: async (): Promise<SignalTeamConfigApi | null> =>
                values.currentProjectId == null ? null : signalsConfigList(String(values.currentProjectId)),
            saveSteeringInstructions: async ({
                role,
                instructions,
            }: SaveSteeringInstructions): Promise<SignalTeamConfigApi> =>
                signalsConfigCreate(String(values.currentProjectId), { [STEERING_FIELDS[role]]: instructions }),
        },
    })),
    reducers({
        selectedRole: ['research' as SteeringRole, { selectRole: (_, { role }) => role }],
        drafts: [
            {} as Partial<Record<SteeringRole, string>>,
            {
                setDraft: (state, { role, instructions }) => ({ ...state, [role]: instructions }),
                discardDraft: (state, { role }) => {
                    const next = { ...state }
                    delete next[role]
                    return next
                },
                saveSteeringInstructionsSuccess: (state, { payload }) => {
                    if (!payload || state[payload.role] !== payload.instructions) {
                        return state
                    }
                    const next = { ...state }
                    delete next[payload.role]
                    return next
                },
            },
        ],
    }),
    selectors({
        dirtyRoles: [
            (s) => [s.drafts, s.steeringConfig],
            (drafts: Partial<Record<SteeringRole, string>>, config: SignalTeamConfigApi | null): SteeringRole[] =>
                config === null
                    ? []
                    : (Object.keys(STEERING_FIELDS) as SteeringRole[]).filter(
                          (role) => drafts[role] !== undefined && drafts[role] !== (config[STEERING_FIELDS[role]] ?? '')
                      ),
        ],
        storedInstructions: [
            (s) => [s.steeringConfig, s.selectedRole],
            (config: SignalTeamConfigApi | null, role: SteeringRole): string | null =>
                config === null ? null : (config[STEERING_FIELDS[role]] ?? ''),
        ],
        instructions: [
            (s) => [s.drafts, s.selectedRole, s.storedInstructions],
            (drafts: Partial<Record<SteeringRole, string>>, role: SteeringRole, stored: string | null): string =>
                drafts[role] ?? stored ?? '',
        ],
        instructionsDirty: [
            (s) => [s.instructions, s.storedInstructions],
            (instructions: string, stored: string | null): boolean => stored !== null && instructions !== stored,
        ],
    }),
    listeners(({ actions, values }) => ({
        submitInstructions: () => {
            if (values.steeringConfigLoading || !values.instructionsDirty || values.currentProjectId == null) {
                return
            }
            actions.saveSteeringInstructions({ role: values.selectedRole, instructions: values.instructions })
        },
        saveSteeringInstructionsSuccess: () => {
            lemonToast.success('Steering instructions saved')
        },
    })),
    afterMount(({ actions }) => actions.loadSteeringConfig()),
])
