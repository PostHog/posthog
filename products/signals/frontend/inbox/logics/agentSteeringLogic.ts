export interface agentSteeringLogicValues {
    currentProjectId: number | null // projectLogic
    dirtyRoles: SteeringRole[]
    drafts: Partial<Record<SteeringRole, string>>
    instructions: string
    instructionsDirty: boolean
    selectedRole: SteeringRole
    steeringConfig: SignalTeamConfigApi | null
    steeringConfigLoading: boolean
    storedInstructions: string | null
}

