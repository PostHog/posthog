import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { projectLogic } from 'scenes/projectLogic'

import { signalsConfigCreate, signalsConfigList } from '../../generated/api'
import type { SignalTeamConfigApi } from '../../generated/api.schemas'

export const STEERING_FIELDS = {
    scout: 'scout_instructions',
    research: 'research_instructions',
    implementation: 'implementation_instructions',
} as const

export type SteeringRole = keyof typeof STEERING_FIELDS

export interface SaveSteeringInstructions {
    role: SteeringRole
    instructions: string
}

