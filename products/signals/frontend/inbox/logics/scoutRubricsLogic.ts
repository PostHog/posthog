export const scoutRubricsLogic: LogicWrapper<scoutRubricsLogicType> = kea<scoutRubricsLogicType>([
    props({} as ScoutRubricsLogicProps),
    key(({ teamId, configId }) => `${teamId}:${configId}`),
    path((key) => ['products', 'signals', 'inbox', 'logics', 'scoutRubricsLogic', key]),
    actions({
        resetDraft: (document: ScoutRubricDocumentApi) => ({ document }),
        updateCriterion: (id: string, changes: Partial<ScoutRubricCriterionApi>) => ({ id, changes }),
        removeCriterion: (id: string) => ({ id }),
        addCriterion: true,
        appendCriteria: (criteria: ScoutRubricCriterionApi[]) => ({ criteria }),
        setExpandedCriterion: (id: string | null) => ({ id }),
        toggleSuggestion: (id: string, selected: boolean) => ({ id, selected }),
        toggleAllSuggestions: (selected: boolean) => ({ selected }),
        updateSuggestion: (id: string, changes: Partial<ScoutRubricCriterionApi>) => ({ id, changes }),
        resetSuggestions: (generationId: string | null) => ({ generationId }),
        syncGeneration: true,
        setNow: (now: number) => ({ now }),
        setGenerationContext: (context: string) => ({ context }),
        generateSuggestions: true,
        generationRequestStarted: true,
        generationStarted: (document: ScoutRubricDocumentApi) => ({ document }),
        generationFailed: (message: string) => ({ message }),
        generationFinished: true,
        saveRubrics: true,
        saveStarted: true,
        saveSucceeded: (document: ScoutRubricDocumentApi) => ({ document }),
        saveFailed: (message: string, conflict: boolean) => ({ message, conflict }),
        saveFinished: true,
        loadFailed: (message: string) => ({ message }),
    }),
    loaders(({ props, actions, cache, values }) => ({
        rubricDocument: [
            null as ScoutRubricDocumentApi | null,
            {
                loadRubrics: async (
                    options: { resetDraft?: boolean } = {},
                    breakpoint
                ): Promise<ScoutRubricDocumentApi | null> => {
                    const documentVersion = cache.documentVersion ?? 0
                    try {
                        const document = await signalsScoutRubricsRetrieve(String(props.teamId), props.configId)
                        breakpoint()
                        if (documentVersion !== (cache.documentVersion ?? 0)) {
                            return values.rubricDocument
                        }
                        if (options.resetDraft) {
                            actions.resetDraft(document)
                        }
                        return document
                    } catch (error) {
                        breakpoint()
                        actions.loadFailed(readableErrorMessage(error) || 'Could not load rubrics. Try again.')
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        rubricDocument: {
            generationStarted: (_, { document }) => document,
            saveSucceeded: (_, { document }) => document,
        },
        draftCriteria: [
            [] as ScoutRubricCriterionApi[],
            {
                resetDraft: (_, { document }) => document.criteria,
                updateCriterion: (state, { id, changes }) =>
                    state.map((criterion) => (criterion.id === id ? { ...criterion, ...changes } : criterion)),
                removeCriterion: (state, { id }) => state.filter((criterion) => criterion.id !== id),
                appendCriteria: (state, { criteria }) => [...state, ...criteria],
            },
        ],
        draftBaseline: [[] as ScoutRubricCriterionApi[], { resetDraft: (_, { document }) => document.criteria }],
        draftRevision: [null as number | null, { resetDraft: (_, { document }) => document.revision }],
        expandedCriterionId: [
            null as string | null,
            {
                setExpandedCriterion: (_, { id }) => id,
                resetDraft: () => null,
            },
        ],
        selectedSuggestionIds: [
            [] as string[],
            {
                toggleSuggestion: (state, { id, selected }) =>
                    selected ? Array.from(new Set([...state, id])) : state.filter((selectedId) => selectedId !== id),
                updateSuggestion: (state, { id }) => Array.from(new Set([...state, id])),
                resetSuggestions: () => [],
                resetDraft: () => [],
            },
        ],
        suggestionOverrides: [
            {} as Record<string, Partial<ScoutRubricCriterionApi>>,
            {
                updateSuggestion: (state, { id, changes }) => ({ ...state, [id]: { ...state[id], ...changes } }),
                resetSuggestions: () => ({}),
            },
        ],
        suggestionGenerationId: [null as string | null, { resetSuggestions: (_, { generationId }) => generationId }],
        now: [Date.now(), { setNow: (_, { now }) => now }],
        generationSubmitting: [false, { generationRequestStarted: () => true, generationFinished: () => false }],
        generationContext: ['', { setGenerationContext: (_, { context }) => context }],
        generationError: [
            null as string | null,
            { generateSuggestions: () => null, generationFailed: (_, { message }) => message },
        ],
        saving: [false, { saveStarted: () => true, saveFinished: () => false }],
        saveError: [
            null as string | null,
            { saveStarted: () => null, saveFailed: (_, { message }) => message, resetDraft: () => null },
        ],
        saveConflict: [false, { saveFailed: (_, { conflict }) => conflict, resetDraft: () => false }],
        loadError: [null as string | null, { loadFailed: (_, { message }) => message, loadRubricsSuccess: () => null }],
    }),
    selectors({
        generation: [
            (s) => [s.rubricDocument],
            (document: ScoutRubricDocumentApi | null): ScoutRubricDocumentApi['generation'] =>
                document?.generation ?? null,
        ],
        generationActive: [
            (s) => [s.generation],
            (generation: ScoutRubricDocumentApi['generation']): boolean =>
                generation?.status === 'queued' || generation?.status === 'running',
        ],
        generationElapsedLabel: [
            (s) => [s.generation, s.generationActive, s.now],
            (generation: ScoutRubricDocumentApi['generation'], active: boolean, now: number): string | null => {
                const requestedAt = generation ? Date.parse(generation.requested_at) : NaN
                if (!active || !Number.isFinite(requestedAt)) {
                    return null
                }
                const seconds = Math.max(0, Math.floor((now - requestedAt) / 1000))
                return `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, '0')}`
            },
        ],
        hasUnsavedChanges: [
            (s) => [s.criteriaToSave, s.draftBaseline],
            (criteria: ScoutRubricCriterionApi[], baseline: ScoutRubricCriterionApi[]): boolean =>
                JSON.stringify(criteria) !== JSON.stringify(baseline),
        ],
        availableSuggestions: [
            (s) => [s.generation, s.draftCriteria, s.suggestionOverrides],
            (
                generation: ScoutRubricDocumentApi['generation'],
                criteria: ScoutRubricCriterionApi[],
                overrides: Record<string, Partial<ScoutRubricCriterionApi>>
            ): ScoutRubricCriterionApi[] =>
                (generation?.suggestions ?? [])
                    .filter((item) => !criteria.some(({ id }) => id === item.id))
                    .map((item) => ({ ...item, ...overrides[item.id] })),
        ],
        selectedSuggestions: [
            (s) => [s.availableSuggestions, s.selectedSuggestionIds],
            (suggestions: ScoutRubricCriterionApi[], ids: string[]): ScoutRubricCriterionApi[] =>
                suggestions.filter(({ id }) => ids.includes(id)),
        ],
        allSuggestionsSelected: [
            (s) => [s.availableSuggestions, s.selectedSuggestionIds],
            (suggestions: ScoutRubricCriterionApi[], ids: string[]): boolean =>
                suggestions.length > 0 && suggestions.every(({ id }) => ids.includes(id)),
        ],
        criteriaToSave: [
            (s) => [s.draftCriteria, s.selectedSuggestions],
            (
                criteria: ScoutRubricCriterionApi[],
                suggestions: ScoutRubricCriterionApi[]
            ): ScoutRubricCriterionApi[] => [...criteria, ...suggestions],
        ],
        newCriteriaCount: [
            (s) => [s.criteriaToSave, s.draftBaseline],
            (criteria: ScoutRubricCriterionApi[], baseline: ScoutRubricCriterionApi[]): number =>
                criteria.filter(({ id }) => !baseline.some((saved) => saved.id === id)).length,
        ],
        customCriteria: [
            (s) => [s.draftCriteria],
            (criteria: ScoutRubricCriterionApi[]): ScoutRubricCriterionApi[] =>
                criteria.filter(({ source }) => source === 'custom'),
        ],
        sharedCriteria: [
            (s) => [s.draftCriteria],
            (criteria: ScoutRubricCriterionApi[]): ScoutRubricCriterionApi[] =>
                criteria.filter(({ source }) => source === 'default'),
        ],
        validationError: [
            (s) => [s.criteriaToSave],
            (criteria: ScoutRubricCriterionApi[]): string | null => {
                if (criteria.length > MAX_SCOUT_RUBRICS) {
                    return `Keep at most ${MAX_SCOUT_RUBRICS} criteria.`
                }
                if (
                    criteria.some(
                        (item) =>
                            !item.title.trim() ||
                            !item.description.trim() ||
                            !item.pass_condition.trim() ||
                            !item.applicability.trim()
                    )
                ) {
                    return 'Give each criterion a name, a check, a pass condition, and when it applies.'
                }
                return null
            },
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        loadRubricsSuccess: ({ rubricDocument }) => {
            if (values.draftRevision === null && rubricDocument) {
                actions.resetDraft(rubricDocument)
            }
            actions.syncGeneration()
        },
        generationStarted: () => actions.syncGeneration(),
        saveSucceeded: () => actions.syncGeneration(),
        syncGeneration: () => {
            const generationId = values.generation?.id ?? null
            if (generationId !== values.suggestionGenerationId) {
                actions.resetSuggestions(generationId)
            }
            if (values.generationActive) {
                cache.disposables.add(() => {
                    actions.setNow(Date.now())
                    const timer = setInterval(() => actions.setNow(Date.now()), GENERATION_CLOCK_INTERVAL_MS)
                    return () => clearInterval(timer)
                }, 'generationClock')
            } else {
                cache.disposables.dispose('generationClock')
            }
        },
        addCriterion: () => {
            if (values.saving || values.draftCriteria.length >= MAX_SCOUT_RUBRICS) {
                return
            }
            const id = `custom-${uuid()}`
            actions.appendCriteria([
                {
                    id,
                    title: '',
                    description: '',
                    pass_condition: '',
                    applicability: 'All runs.',
                    enabled: true,
                    source: 'custom',
                },
            ])
            actions.setExpandedCriterion(id)
        },
        toggleAllSuggestions: ({ selected }) => {
            if (values.saving) {
                return
            }
            values.availableSuggestions.forEach(({ id }) => actions.toggleSuggestion(id, selected))
        },
        generateSuggestions: async () => {
            if (values.generationSubmitting || values.generationActive || values.saving || values.hasUnsavedChanges) {
                return
            }
            actions.generationRequestStarted()
            const context = getContext()
            const disposables = cache.disposables
            const submittedContext = values.generationContext.trim()
            try {
                const document = await signalsScoutRubricsGenerate(String(props.teamId), props.configId, {
                    context: submittedContext,
                })
                if (!disposables.isDisposed && getContext() === context) {
                    cache.documentVersion = (cache.documentVersion ?? 0) + 1
                    actions.generationStarted(document)
                    // When a generation is already active, the API returns it with the focus of the session that
                    // started it. Clear the text only when the active generation received it.
                    if (document.generation?.context === submittedContext) {
                        actions.setGenerationContext('')
                    } else if (submittedContext) {
                        lemonToast.info(
                            'Another session already started generating suggestions, so your focus was not used. It stays here for your next generation.'
                        )
                    }
                }
            } catch (error) {
                if (!disposables.isDisposed && getContext() === context) {
                    actions.generationFailed(readableErrorMessage(error) || 'Could not start generation. Try again.')
                }
            } finally {
                if (!disposables.isDisposed && getContext() === context) {
                    actions.generationFinished()
                }
            }
        },
        saveRubrics: async () => {
            if (values.saving || values.validationError || values.saveConflict || values.draftRevision === null) {
                return
            }
            actions.saveStarted()
            const context = getContext()
            const disposables = cache.disposables
            try {
                const document = await signalsScoutRubricsUpdate(String(props.teamId), props.configId, {
                    revision: values.draftRevision,
                    criteria: values.criteriaToSave,
                })
                if (!disposables.isDisposed && getContext() === context) {
                    cache.documentVersion = (cache.documentVersion ?? 0) + 1
                    actions.saveSucceeded(document)
                    actions.resetDraft(document)
                    lemonToast.success('Rubrics saved')
                }
            } catch (error) {
                if (!disposables.isDisposed && getContext() === context) {
                    const conflict = error instanceof ApiError && error.status === 409
                    actions.saveFailed(
                        conflict
                            ? 'These rubrics changed in another session. Your edits are still here. Reload the saved version before editing again.'
                            : readableErrorMessage(error) ||
                                  'Could not save rubrics. Your edits are still here. Try again.',
                        conflict
                    )
                }
            } finally {
                if (!disposables.isDisposed && getContext() === context) {
                    actions.saveFinished()
                }
            }
        },
    })),
    afterMount(({ actions, values, cache }) => {
        actions.loadRubrics()
        cache.disposables.add(() => {
            const timer = setInterval(() => {
                if (values.generationActive && !values.rubricDocumentLoading) {
                    actions.loadRubrics()
                }
            }, GENERATION_POLL_INTERVAL_MS)
            return () => clearInterval(timer)
        })
    }),
])
