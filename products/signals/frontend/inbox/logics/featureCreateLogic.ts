import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { router } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import { ApiError } from 'lib/api-error'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { signalsFeaturesCreate } from 'products/signals/frontend/generated/api'

function featureCreateErrorMessage(error: unknown): string {
    if (error instanceof ApiError) {
        return error.detail || error.message
    }
    return error instanceof Error ? error.message : 'Failed to create feature'
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureCreateLogicValues {
    currentProjectId: number | string // teamLogic
    creating: boolean
    descriptionDraft: string
    newFeatureModalOpen: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureCreateLogicActions {
    closeNewFeatureModal: () => {
        value: true
    }
    createFeature: () => {
        value: true
    }
    openNewFeatureModal: () => {
        value: true
    }
    setCreating: (creating: boolean) => {
        creating: boolean
    }
    setDescriptionDraft: (draft: string) => {
        draft: string
    }
}

export type featureCreateLogicType = MakeLogicType<featureCreateLogicValues, featureCreateLogicActions>

/**
 * The "New feature" flow: a modal asking for a brief initial description, then a create call that
 * lands the user in its live planning conversation.
 */
export const featureCreateLogic = kea<featureCreateLogicType>([
    path(['scenes', 'inbox', 'logics', 'featureCreateLogic']),

    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),

    actions({
        openNewFeatureModal: true,
        closeNewFeatureModal: true,
        setDescriptionDraft: (draft: string) => ({ draft }),
        createFeature: true,
        setCreating: (creating: boolean) => ({ creating }),
    }),

    reducers({
        newFeatureModalOpen: [
            false,
            {
                openNewFeatureModal: () => true,
                closeNewFeatureModal: () => false,
            },
        ],
        descriptionDraft: [
            '',
            {
                setDescriptionDraft: (_, { draft }) => draft,
                closeNewFeatureModal: () => '',
            },
        ],
        creating: [
            false,
            {
                setCreating: (_, { creating }) => creating,
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        createFeature: async () => {
            const description = values.descriptionDraft.trim()
            if (!description) {
                lemonToast.error('Describe the idea first. A sentence is enough.')
                return
            }
            if (values.creating) {
                return
            }
            actions.setCreating(true)
            try {
                const created = await signalsFeaturesCreate(String(values.currentProjectId), {
                    initial_description: description,
                })
                actions.closeNewFeatureModal()
                router.actions.push(urls.inboxReport('features', created.report_id), { feature_tab: 'planning' })
            } catch (error: unknown) {
                lemonToast.error(featureCreateErrorMessage(error))
            } finally {
                actions.setCreating(false)
            }
        },
    })),
])
