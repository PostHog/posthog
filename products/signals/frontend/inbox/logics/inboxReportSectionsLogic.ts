import { MakeLogicType, actions, kea, listeners, path, reducers, selectors } from 'kea'

import { captureInboxSectionToggled } from '../inboxAnalytics'
import { INBOX_REPORT_SECTION_KEYS, InboxReportSectionKey } from '../types'

/** localStorage key for the per-user collapsed/expanded sections (see `sectionOverrides`). */
export const INBOX_OPEN_SECTIONS_STORAGE_KEY = 'inbox-open-report-sections'

/**
 * How a section starts before the user has collapsed or expanded it. The two sections that carry
 * work to do open; the two that are a record of work already judged stay out of the way.
 */
export const DEFAULT_OPEN_SECTIONS: Record<InboxReportSectionKey, boolean> = {
    monitoring: true,
    'needs-decision': true,
    resolved: false,
    'not-actionable': false,
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface inboxReportSectionsLogicValues {
    openSections: Record<InboxReportSectionKey, boolean>
    sectionOverrides: Record<string, boolean>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface inboxReportSectionsLogicActions {
    toggleSection: (section: InboxReportSectionKey) => {
        section: 'monitoring' | 'needs-decision' | 'not-actionable' | 'resolved'
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface inboxReportSectionsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        openSections: (sectionOverrides: Record<string, boolean>) => Record<InboxReportSectionKey, boolean>
    }
}

export type inboxReportSectionsLogicType = MakeLogicType<
    inboxReportSectionsLogicValues,
    inboxReportSectionsLogicActions,
    Record<string, any>,
    inboxReportSectionsLogicMeta
>

/**
 * Which Reports sections are expanded. Persisted, so a user who collapses Monitoring finds it
 * collapsed on their next visit.
 *
 * Only sections the user has actually toggled are stored. Everything else reads through to
 * `DEFAULT_OPEN_SECTIONS`, so a changed default reaches every user who never expressed a
 * preference, and a section added later starts at its own default rather than at `false`.
 */
export const inboxReportSectionsLogic = kea<inboxReportSectionsLogicType>([
    path(['scenes', 'inbox', 'logics', 'inboxReportSectionsLogic']),

    actions({
        toggleSection: (section: InboxReportSectionKey) => ({ section }),
    }),

    reducers({
        sectionOverrides: [
            {} as Record<string, boolean>,
            { persist: true, storageKey: INBOX_OPEN_SECTIONS_STORAGE_KEY },
            {
                toggleSection: (state, { section }) => ({
                    ...state,
                    [section]: !(state[section] ?? DEFAULT_OPEN_SECTIONS[section]),
                }),
            },
        ],
    }),

    listeners(({ values }) => ({
        // Listeners run after reducers, so `openSections` already holds the new state.
        toggleSection: ({ section }) => captureInboxSectionToggled({ section, isOpen: values.openSections[section] }),
    })),

    selectors({
        openSections: [
            (s) => [s.sectionOverrides],
            (sectionOverrides: Record<string, boolean>): Record<InboxReportSectionKey, boolean> =>
                Object.fromEntries(
                    INBOX_REPORT_SECTION_KEYS.map((section) => [
                        section,
                        sectionOverrides[section] ?? DEFAULT_OPEN_SECTIONS[section],
                    ])
                ) as Record<InboxReportSectionKey, boolean>,
        ],
    }),
])
