export const alertNamePatternsLogic: LogicWrapper<alertNamePatternsLogicType> = kea<alertNamePatternsLogicType>([
    path(['scenes', 'inbox', 'logics', 'alertNamePatternsLogic']),
    props({} as AlertNamePatternsLogicProps),
    key((logicProps) => logicProps.sourceConfig.id),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], signalSourcesLogic, ['anomalyInvestigationConfig']],
        actions: [signalSourcesLogic, ['replaceSourceConfig']],
    })),
    actions({
        setAllowText: (text: string) => ({ text }),
        setBlockText: (text: string) => ({ text }),
        discard: true,
        loadPreview: true,
        loadPreviewSuccess: (preview: AlertPatternPreviewResponseApi) => ({ preview }),
        loadPreviewFailure: true,
        save: true,
        saveComplete: true,
    }),
    reducers(({ props: logicProps }) => ({
        allowText: [
            alertPatternsFromConfig(logicProps.sourceConfig.config, SOURCE_ALERT_ALLOW_PATTERNS_KEY).join('\n'),
            { setAllowText: (_, { text }) => text },
        ],
        blockText: [
            alertPatternsFromConfig(logicProps.sourceConfig.config, SOURCE_ALERT_BLOCK_PATTERNS_KEY).join('\n'),
            { setBlockText: (_, { text }) => text },
        ],
        preview: [null as AlertPatternPreviewResponseApi | null, { loadPreviewSuccess: (_, { preview }) => preview }],
        previewLoading: [
            false,
            { loadPreview: () => true, loadPreviewSuccess: () => false, loadPreviewFailure: () => false },
        ],
        previewFailed: [
            false,
            { loadPreview: () => false, loadPreviewSuccess: () => false, loadPreviewFailure: () => true },
        ],
        saving: [false, { save: () => true, saveComplete: () => false }],
    })),
    selectors({
        // The cached row is the one a save replaces, so it is current before the props catch up.
        savedConfig: [
            (s, p) => [s.anomalyInvestigationConfig, p.sourceConfig],
            (
                anomalyInvestigationConfig: SignalSourceConfig | null,
                sourceConfig: SignalSourceConfig
            ): SignalSourceConfig => anomalyInvestigationConfig ?? sourceConfig,
        ],
        savedAllowPatterns: [
            (s) => [s.savedConfig],
            (savedConfig: SignalSourceConfig): string[] =>
                alertPatternsFromConfig(savedConfig.config, SOURCE_ALERT_ALLOW_PATTERNS_KEY),
        ],
        savedBlockPatterns: [
            (s) => [s.savedConfig],
            (savedConfig: SignalSourceConfig): string[] =>
                alertPatternsFromConfig(savedConfig.config, SOURCE_ALERT_BLOCK_PATTERNS_KEY),
        ],
        allowPatterns: [(s) => [s.allowText], (allowText: string): string[] => patternsFromText(allowText)],
        blockPatterns: [(s) => [s.blockText], (blockText: string): string[] => patternsFromText(blockText)],
        hasChanges: [
            (s) => [s.allowPatterns, s.blockPatterns, s.savedAllowPatterns, s.savedBlockPatterns],
            (
                allowPatterns: string[],
                blockPatterns: string[],
                savedAllowPatterns: string[],
                savedBlockPatterns: string[]
            ): boolean =>
                !samePatterns(allowPatterns, savedAllowPatterns) || !samePatterns(blockPatterns, savedBlockPatterns),
        ],
        patternErrors: [
            (s) => [s.preview],
            (preview: AlertPatternPreviewResponseApi | null): { allow: string | null; block: string | null } => ({
                allow: preview?.alert_allow_patterns_error ?? null,
                block: preview?.alert_block_patterns_error ?? null,
            }),
        ],
        previewGroups: [
            (s) => [s.preview, s.patternErrors],
            (
                preview: AlertPatternPreviewResponseApi | null,
                patternErrors: { allow: string | null; block: string | null }
            ): AlertPatternPreviewGroups | null =>
                !preview || patternErrors.allow || patternErrors.block
                    ? null
                    : {
                          passed: preview.alerts.filter((alert) => alert.outcome === 'passed'),
                          dropped: preview.alerts.filter((alert) => alert.outcome !== 'passed'),
                      },
        ],
        // The preview checks the same rules the save does, so a save waits for it rather than racing a 400.
        canSave: [
            (s) => [s.hasChanges, s.saving, s.previewLoading, s.patternErrors],
            (
                hasChanges: boolean,
                saving: boolean,
                previewLoading: boolean,
                patternErrors: { allow: string | null; block: string | null }
            ): boolean => hasChanges && !saving && !previewLoading && !patternErrors.allow && !patternErrors.block,
        ],
    }),
    listeners(({ actions, values, props: logicProps }) => ({
        setAllowText: () => actions.loadPreview(),
        setBlockText: () => actions.loadPreview(),
        discard: () => {
            actions.setAllowText(values.savedAllowPatterns.join('\n'))
            actions.setBlockText(values.savedBlockPatterns.join('\n'))
        },
        loadPreview: async (_, breakpoint) => {
            await breakpoint(PREVIEW_DEBOUNCE_MS)
            let preview: AlertPatternPreviewResponseApi
            try {
                preview = await signalsSourceConfigsAlertPatternPreviewCreate(String(values.currentTeamId), {
                    alert_allow_patterns: values.allowPatterns,
                    alert_block_patterns: values.blockPatterns,
                })
            } catch {
                breakpoint()
                actions.loadPreviewFailure()
                return
            }
            breakpoint()
            actions.loadPreviewSuccess(preview)
        },
        save: async () => {
            const allow = values.allowPatterns
            const block = values.blockPatterns
            const analyticsParams = {
                allowCount: allow.length,
                blockCount: block.length,
                droppedAlertCount: values.previewGroups?.dropped.length ?? null,
            }
            try {
                const updated = await signalsSourceConfigsPartialUpdate(
                    String(values.currentTeamId),
                    logicProps.sourceConfig.id,
                    {
                        config_set: {
                            [SOURCE_ALERT_ALLOW_PATTERNS_KEY]: allow,
                            [SOURCE_ALERT_BLOCK_PATTERNS_KEY]: block,
                        },
                    }
                )
                // Read the row again: an on/off toggle may have changed it while this save ran.
                const latest = values.savedConfig
                actions.replaceSourceConfig({
                    ...latest,
                    config: updated.config ?? latest.config,
                    updated_at: updated.updated_at,
                })
                // Show the patterns as stored, without the blank lines and spaces the save dropped.
                actions.setAllowText(allow.join('\n'))
                actions.setBlockText(block.join('\n'))
                captureSignalSourceAlertPatternsChanged({ ...analyticsParams, success: true })
                lemonToast.success('Alert filters saved. They apply to alerts from now on.')
            } catch (error) {
                captureSignalSourceAlertPatternsChanged({ ...analyticsParams, success: false })
                const apiError = error instanceof ApiError ? error : null
                lemonToast.error(apiError?.detail ?? "Couldn't save your alert filters. Try again.")
            } finally {
                actions.saveComplete()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadPreview()
    }),
])
