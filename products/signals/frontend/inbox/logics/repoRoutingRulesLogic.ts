/**
 * CRUD state for the team's repo routing rules, shown in the Code access settings section.
 * The same rows the Slack `@PostHog rules` commands manage; the repo selection agent reads
 * them ordered by priority when picking a repository. All mutations resolve to the full
 * updated list so the loader stays the single source of truth.
 */
export const repoRoutingRulesLogic = kea<repoRoutingRulesLogicType>([
    path(['products', 'signals', 'frontend', 'inbox', 'logics', 'repoRoutingRulesLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        deleteRule: (rule: RepoRoutingRuleApi) => ({ rule }),
        setDraftRuleText: (ruleText: string) => ({ ruleText }),
        setDraftRepository: (repository: string) => ({ repository }),
        setDraftIntegrationId: (integrationId: number | null) => ({ integrationId }),
        startEditingRule: (rule: RepoRoutingRuleApi, integrationId: number | null) => ({ rule, integrationId }),
        cancelEditingRule: true,
        setEditRuleText: (ruleText: string) => ({ ruleText }),
        setEditRepository: (repository: string) => ({ repository }),
        setEditIntegrationId: (integrationId: number | null) => ({ integrationId }),
    }),
    loaders(({ values }) => ({
        rules: [
            null as RepoRoutingRuleApi[] | null,
            {
                loadRules: async () => {
                    return await tasksRepoRoutingRulesList(String(values.currentTeamId))
                },
                addRule: async () => {
                    const created = await tasksRepoRoutingRulesCreate(String(values.currentTeamId), {
                        rule_text: values.draftRuleText.trim(),
                        repository: values.draftRepository,
                    })
                    return [...(values.rules ?? []), created]
                },
                saveEditedRule: async () => {
                    if (!values.editingRuleId) {
                        return values.rules
                    }
                    const updated = await tasksRepoRoutingRulesPartialUpdate(
                        String(values.currentTeamId),
                        values.editingRuleId,
                        { rule_text: values.editRuleText.trim(), repository: values.editRepository }
                    )
                    return (values.rules ?? []).map((rule) => (rule.id === updated.id ? updated : rule))
                },
                deleteRule: async ({ rule }) => {
                    await tasksRepoRoutingRulesDestroy(String(values.currentTeamId), rule.id)
                    return (values.rules ?? []).filter((row) => row.id !== rule.id)
                },
            },
        ],
    })),
    reducers({
        draftRuleText: ['', { setDraftRuleText: (_, { ruleText }) => ruleText, addRuleSuccess: () => '' }],
        draftRepository: [
            '',
            {
                setDraftRepository: (_, { repository }) => repository,
                addRuleSuccess: () => '',
                // Another installation's repositories are a different set, so a kept selection
                // would submit a repo the shown org does not have.
                setDraftIntegrationId: () => '',
            },
        ],
        draftIntegrationId: [null as number | null, { setDraftIntegrationId: (_, { integrationId }) => integrationId }],
        editingRuleId: [
            null as string | null,
            {
                startEditingRule: (_, { rule }) => rule.id,
                cancelEditingRule: () => null,
                saveEditedRuleSuccess: () => null,
            },
        ],
        editRuleText: [
            '',
            { startEditingRule: (_, { rule }) => rule.rule_text, setEditRuleText: (_, { ruleText }) => ruleText },
        ],
        editRepository: [
            '',
            {
                startEditingRule: (_, { rule }) => rule.repository,
                setEditRepository: (_, { repository }) => repository,
                setEditIntegrationId: () => '',
            },
        ],
        editIntegrationId: [
            null as number | null,
            {
                startEditingRule: (_, { integrationId }) => integrationId,
                setEditIntegrationId: (_, { integrationId }) => integrationId,
            },
        ],
    }),
    selectors({
        addRuleDisabledReason: [
            (s) => [s.draftRuleText, s.draftRepository, s.rules],
            (draftRuleText: string, draftRepository: string, rules: RepoRoutingRuleApi[] | null): string | null => {
                if ((rules?.length ?? 0) >= MAX_RULES_PER_TEAM) {
                    return `Limit of ${MAX_RULES_PER_TEAM} rules reached. Remove a rule to add another.`
                }
                return ruleDisabledReason(draftRuleText, draftRepository)
            },
        ],
        saveEditedRuleDisabledReason: [
            (s) => [s.editRuleText, s.editRepository],
            (editRuleText: string, editRepository: string): string | null =>
                ruleDisabledReason(editRuleText, editRepository),
        ],
    }),
    listeners(() => ({
        addRuleSuccess: () => {
            captureInboxSettingsChanged({
                setting: 'repo_routing_rule_added',
                newValue: null,
                success: true,
                scope: 'team',
            })
        },
        saveEditedRuleSuccess: () => {
            captureInboxSettingsChanged({
                setting: 'repo_routing_rule_updated',
                newValue: null,
                success: true,
                scope: 'team',
            })
        },
        deleteRuleSuccess: () => {
            captureInboxSettingsChanged({
                setting: 'repo_routing_rule_removed',
                newValue: null,
                success: true,
                scope: 'team',
            })
        },
        // No toasts here: the global kea loaders failure handler already raises one with the
        // server's error detail. These listeners only record the rejected change.
        addRuleFailure: () => {
            captureInboxSettingsChanged({
                setting: 'repo_routing_rule_added',
                newValue: null,
                success: false,
                scope: 'team',
            })
        },
        saveEditedRuleFailure: () => {
            captureInboxSettingsChanged({
                setting: 'repo_routing_rule_updated',
                newValue: null,
                success: false,
                scope: 'team',
            })
        },
        deleteRuleFailure: () => {
            captureInboxSettingsChanged({
                setting: 'repo_routing_rule_removed',
                newValue: null,
                success: false,
                scope: 'team',
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRules()
    }),
])

function ruleDisabledReason(ruleText: string, repository: string): string | null {
    if (!ruleText.trim()) {
        return 'Describe which requests the rule matches'
    }
    if (ruleText.trim().length > MAX_RULE_TEXT_LENGTH) {
        return `Keep the rule under ${MAX_RULE_TEXT_LENGTH} characters`
    }
    if (!repository) {
        return 'Pick a repository'
    }
    return null
}
