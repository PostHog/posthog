import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { combineUrl, router } from 'kea-router'

import { getGithubSetupErrorCode } from 'lib/integrations/githubSetupErrors'
import { integrationsLogic } from 'lib/integrations/integrationsLogic'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { getIntegrationsAuthorizeRetrieveUrl } from 'products/integrations/frontend/generated/api'

import { inboxSetupLogic } from './inboxSetupLogic'

export type InboxAgentActivationView = 'connecting' | 'activating' | 'confirm' | 'done' | 'error'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface inboxAgentActivationLogicValues {
    error: string | null // inboxSetupLogic
    completed: boolean // inboxSetupLogic
    saving: boolean // inboxSetupLogic
    quickActivationPending: boolean // inboxSetupLogic
    hasGithubIntegration: boolean // inboxSetupLogic
    currentTeamId: number | null // teamLogic
    searchParams: Record<string, any> // router
    resumeChecked: boolean
    withoutGithub: boolean
    returningFromGithub: boolean
    view: InboxAgentActivationView
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface inboxAgentActivationLogicActions {
    start: () => {
        value: true
    }
    resume: () => {
        value: true
    }
    retry: () => {
        value: true
    }
    setResumeChecked: () => {
        value: true
    }
}

