export type inboxAgentActivationLogicType = MakeLogicType<
    inboxAgentActivationLogicValues,
    inboxAgentActivationLogicActions,
    Record<string, any>,
    inboxAgentActivationLogicMeta
>

export const inboxAgentActivationLogic = kea<inboxAgentActivationLogicType>([
    path(['products', 'signals', 'inbox', 'inboxAgentActivationLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            inboxSetupLogic,
            ['error', 'completed', 'saving', 'quickActivationPending', 'hasGithubIntegration'],
            router,
            ['searchParams'],
        ],
    })),
    actions({ start: true, resume: true, retry: true, setResumeChecked: true }),
    reducers({
        // Separates "still checking the GitHub return" from "checked, and it needs a click", so the page never offers
        // a button while the automatic activation may still start.
        resumeChecked: [false, { setResumeChecked: () => true, start: () => false }],
    }),
    selectors({
        withoutGithub: [
            () => [router.selectors.location],
            (location: { pathname: string }): boolean => location.pathname.endsWith(urls.inboxActivateWithoutGithub()),
        ],
        returningFromGithub: [
            (s) => [s.searchParams],
            (searchParams: Record<string, any>): boolean => searchParams.agent_setup === 'return',
        ],
        view: [
            (s) => [s.error, s.completed, s.saving, s.quickActivationPending, s.returningFromGithub, s.resumeChecked],
            (
                error: string | null,
                completed: boolean,
                saving: boolean,
                quickActivationPending: boolean,
                returningFromGithub: boolean,
                resumeChecked: boolean
            ): InboxAgentActivationView =>
                error
                    ? 'error'
                    : completed
                      ? 'done'
                      : saving || quickActivationPending
                        ? 'activating'
                        : returningFromGithub
                          ? resumeChecked
                              ? 'confirm'
                              : 'activating'
                          : 'connecting',
        ],
    }),
    listeners(({ actions, values }) => ({
        start: async (_, breakpoint) => {
            const projectId = values.currentTeamId
            if (!projectId || inboxSetupLogic.values.saving) {
                return
            }
            inboxSetupLogic.actions.setError(null)
            await inboxSetupLogic.asyncActions.loadSetup()
            breakpoint()
            if (projectId !== values.currentTeamId || values.error) {
                return
            }
            const state = inboxSetupLogic.values.savedState
            if (!state || state.completed_at) {
                return
            }
            if (state.draft) {
                router.actions.replace(urls.inbox(), {
                    onboarding_step: state.draft.step,
                    agent_setup: 'return',
                })
                return
            }
            if (values.withoutGithub && state.github_optional_available) {
                router.actions.replace(urls.inbox(), {
                    setup: 'github-first',
                    onboarding_step: 'quick',
                    agent_setup: 'without_github',
                })
                return
            }
            if (values.returningFromGithub) {
                actions.resume()
                return
            }
            const next = urls.project(
                projectId,
                combineUrl(urls.inboxActivate(), { onboarding_step: 'quick', agent_setup: 'return' }).url
            )
            const authorizeUrl = combineUrl(getIntegrationsAuthorizeRetrieveUrl(String(projectId)), {
                kind: 'github',
                next,
            }).url
            router.actions.replace(urls.inboxActivate(), { onboarding_step: 'quick' })
            inboxSetupLogic.actions.expose()
            inboxSetupLogic.actions.connectGithub(authorizeUrl)
        },
        resume: () => {
            const setup = inboxSetupLogic.values
            if (values.resumeChecked || !values.returningFromGithub || !setup.savedState || setup.completed) {
                return
            }
            if (getGithubSetupErrorCode(values.searchParams) || setup.shouldResumeQuickSetup) {
                // Activates only when this tab started the GitHub connection. Otherwise the page asks for a click.
                inboxSetupLogic.actions.resumeQuickSetup()
                actions.setResumeChecked()
            } else if (!setup.integrationsLoading && !setup.hasGithubIntegration) {
                actions.setResumeChecked()
            }
        },
        retry: () => {
            if (values.returningFromGithub && values.hasGithubIntegration) {
                inboxSetupLogic.actions.setError(null)
                inboxSetupLogic.actions.activateQuickSetup('retry')
                return
            }
            router.actions.replace(urls.inboxActivate())
            actions.start()
        },
        [inboxSetupLogic.actionTypes.loadSetupSuccess]: () => actions.resume(),
        [integrationsLogic.actionTypes.loadIntegrationsSuccess]: () => actions.resume(),
        [integrationsLogic.actionTypes.loadIntegrationsFailure]: () => actions.resume(),
    })),
    afterMount(({ actions }) => actions.start()),
])
