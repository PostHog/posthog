export const reportQuickAskLogic = kea<reportQuickAskLogicType>([
    props({} as ReportQuickAskLogicProps),
    key((props) => props.report.id),
    path((key) => ['products', 'signals', 'frontend', 'inbox', 'logics', 'reportQuickAskLogic', key]),
    connect((props: ReportQuickAskLogicProps) => ({
        values: [
            inboxTaskKickoffLogic,
            ['isDiscussing', 'isCreatingPr', 'aiConsentDisabledReason', 'freeTrialDisabledReason'],
            inboxReportDetailLogic({ reportId: props.report.id, report: props.report }),
            ['prChecksFailing', 'prHasConflict', 'selectedPullRequest'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [inboxTaskKickoffLogic, ['quickAskFailed']],
    })),
    actions({
        setQuestion: (question: string) => ({ question }),
        setOpen: (open: boolean) => ({ open }),
        fillFromSuggestion: (suggestion: string) => ({ suggestion }),
        submit: true,
        submitted: true,
        startPrAction: (action: ReportPrAiAction) => ({ action }),
        openInSidebar: true,
    }),
    reducers(({ props }) => ({
        question: [
            '',
            {
                setQuestion: (_, { question }) => question,
                fillFromSuggestion: (_, { suggestion }) => suggestion,
                submitted: () => '',
                // A quick ask closes the dropdown before its run exists, so a failed ask puts the question back.
                quickAskFailed: (state, { reportId, question }) => (reportId === props.report.id ? question : state),
            },
        ],
        // The suggestion the textarea was last filled from, so a submitted question can be reported as
        // sent as written, edited first, or written from scratch. Null until a row is clicked.
        filledFrom: [
            null as string | null,
            { fillFromSuggestion: (_, { suggestion }) => suggestion, submitted: () => null },
        ],
        isOpen: [false, { setOpen: (_, { open }) => open, submitted: () => false, startPrAction: () => false }],
    })),
    selectors({
        // Read through the props, so a report that updates while the page is open updates the quick ask too.
        report: [(_, p) => [p.report], (report: SignalReport): SignalReport => report],
        reportUrl: [(_, p) => [p.reportUrl], (reportUrl: string): string => reportUrl],
        // Suggestions can be action requests, and the kickoff wrapper only carries actions out on
        // action-capable reports, so on any other report a stored suggestion would invite an action the
        // run then merely answers.
        actionCapable: [(s) => [s.report], (report: SignalReport): boolean => isActionCapableReport(report)],
        suggestions: [
            (s) => [s.report, s.actionCapable],
            (report: SignalReport, actionCapable: boolean): string[] =>
                actionCapable ? (report.suggested_prompts ?? []) : [],
        ],
        placeholder: [
            (s) => [s.actionCapable],
            (actionCapable: boolean): string =>
                actionCapable ? 'Ask a question, or tell AI what to do next' : 'Ask a question about this report',
        ],
        disabledReason: [
            (s) => [s.aiConsentDisabledReason, s.isCreatingPr],
            (aiConsentDisabledReason: string | null, isCreatingPr: boolean): string | undefined =>
                aiConsentDisabledReason ?? (isCreatingPr ? 'An implementation is starting.' : undefined),
        ],
        prActions: [
            (s) => [
                s.report,
                s.featureFlags,
                s.prChecksFailing,
                s.prHasConflict,
                s.selectedPullRequest,
                s.freeTrialDisabledReason,
            ],
            (
                report: SignalReport,
                featureFlags: FeatureFlagsSet,
                prChecksFailing: boolean,
                prHasConflict: boolean,
                selectedPullRequest: ReportPullRequest,
                freeTrialDisabledReason: string | null
            ): ReportPrAiAction[] => {
                if (!featureFlags[FEATURE_FLAGS.INBOX_GET_IT_MERGED]) {
                    return []
                }
                const pullRequestUrl = selectedPullRequest.url
                const actions: ReportPrAiAction[] = []
                if (hasApprovedOpenReportPullRequest(report)) {
                    actions.push({
                        key: 'merge_pr',
                        label: 'Get it merged',
                        tooltip: 'Fix CI on the approved PR and merge it',
                        request: MERGE_PR_REQUEST,
                        disabledReason: freeTrialDisabledReason,
                        dataAttr: 'inbox-report-ask-ai-merge-pr',
                    })
                }
                if (prChecksFailing || prHasConflict) {
                    actions.push({
                        key: 'fix_ci',
                        label: 'Make it green',
                        tooltip:
                            'Fix failing CI and merge conflicts on the PR and stop, so you can review and merge it',
                        request: FIX_CI_REQUEST,
                        pullRequestUrl,
                        disabledReason: freeTrialDisabledReason,
                        dataAttr: 'inbox-report-ask-ai-fix-ci',
                    })
                }
                if (prHasConflict) {
                    actions.push({
                        key: 'resolve_conflicts',
                        label: 'Resolve conflicts',
                        tooltip: 'Update the PR from its base branch, resolve the conflicts, and stop',
                        request: RESOLVE_CONFLICTS_REQUEST,
                        pullRequestUrl,
                        disabledReason: freeTrialDisabledReason,
                        dataAttr: 'inbox-report-ask-ai-resolve-conflicts',
                    })
                }
                return actions
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        submit: () => {
            const trimmed = values.question.trim()
            // Enter submits straight from the textarea, so it never sees the button's `loading` or
            // `disabledReason`. Each guard has to hold here too, or a second press starts another run.
            if (
                !trimmed ||
                values.isDiscussing ||
                values.isCreatingPr ||
                Array.from(trimmed).length > REPORT_DISCUSSION_QUESTION_MAX_LENGTH
            ) {
                return
            }
            if (values.aiConsentDisabledReason) {
                lemonToast.error(values.aiConsentDisabledReason)
                return
            }
            captureInboxReportAction({
                report: values.report,
                actionType: 'discuss',
                surface: 'detail_pane',
                extra: {
                    ...discussQuestionProperties({
                        source: questionSource(trimmed, values.filledFrom),
                        suggestionCount: values.suggestions.length,
                    }),
                    launch_mode: 'background',
                },
            })
            inboxTaskKickoffLogic.actions.discussReport(
                values.report,
                values.reportUrl,
                trimmed,
                undefined,
                undefined,
                undefined,
                true
            )
            actions.submitted()
        },
        startPrAction: ({ action }) => {
            captureInboxReportAction({
                report: values.report,
                actionType: 'discuss',
                surface: 'detail_pane',
                extra: discussQuestionProperties({ source: 'suggested', suggestionCount: 1, intent: action.key }),
            })
            inboxTaskKickoffLogic.actions.discussReport(
                values.report,
                values.reportUrl,
                action.request,
                undefined,
                action.key,
                action.pullRequestUrl
            )
        },
        openInSidebar: () => {
            inboxTaskKickoffLogic.actions.openReportDiscussion(values.report, values.reportUrl)
        },
    })),
])
