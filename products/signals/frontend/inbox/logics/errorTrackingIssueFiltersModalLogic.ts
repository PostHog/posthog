// Its own filter state, apart from the Issues screen's, which also writes to the URL.
export const INBOX_ISSUE_FILTERS_LOGIC_KEY = 'inbox-source-issue-filters'
export const ISSUE_FILTERS_QUICK_FILTER_CONTEXT = QuickFilterContext.ErrorTrackingIssueFilters

export interface ErrorTrackingIssueFiltersModalLogicProps {
    /** Every persisted error tracking row. One filter covers the source, so a save writes all of them. */
    sourceConfigs: SignalSourceConfig[]
    onClose: () => void
}

function storedFilters(sourceConfigs: SignalSourceConfig[]): unknown {
    // Saves write every row, so the rows normally agree. After a partial save they can differ, and
    // the filter that is in force somewhere beats a blank form that reads as "nothing is set".
    return sourceConfigs.map((config) => config.config[SOURCE_ISSUE_FILTERS_KEY]).find((value) => !!value) ?? null
}

function selectedOptionId(filterGroup: UniversalFiltersGroup, filter: QuickFilter): string | null {
    const inner = filterGroup.values[0]
    const leaves = isUniversalGroupFilterLike(inner) ? inner.values : []
    const leaf = leaves.find(
        (value): value is AnyPropertyFilter =>
            !isUniversalGroupFilterLike(value) &&
            (value as AnyPropertyFilter).type === PropertyFilterType.Event &&
            (value as AnyPropertyFilter).key === filter.property_name
    )
    if (!leaf) {
        return null
    }
    const option = filter.options.find(
        (candidate: QuickFilterOption) =>
            candidate.operator === ('operator' in leaf ? leaf.operator : undefined) &&
            objectsEqual(candidate.value === null ? undefined : candidate.value, leaf.value)
    )
    return option?.id ?? null
}

