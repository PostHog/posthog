export const errorTrackingIssueFiltersModalLogic: LogicWrapper<errorTrackingIssueFiltersModalLogicType> =
    kea<errorTrackingIssueFiltersModalLogicType>([
        path(['products', 'signals', 'frontend', 'inbox', 'logics', 'errorTrackingIssueFiltersModalLogic']),
        props({} as ErrorTrackingIssueFiltersModalLogicProps),
        key((logicProps) => logicProps.sourceConfigs.map((config) => config.id).join(',')),
        connect(() => ({
            values: [
                teamLogic,
                ['currentTeamId'],
                issueFiltersLogic({ logicKey: INBOX_ISSUE_FILTERS_LOGIC_KEY }),
                ['filterGroup'],
                quickFiltersLogic({ context: ISSUE_FILTERS_QUICK_FILTER_CONTEXT }),
                ['quickFilters'],
            ],
            actions: [
                issueFiltersLogic({ logicKey: INBOX_ISSUE_FILTERS_LOGIC_KEY }),
                ['setFilterGroup'],
                signalSourcesLogic,
                ['loadSourceConfigs', 'replaceSourceConfig'],
            ],
        })),
        actions({
            setSeverity: (severity: IssueSeverity | null) => ({ severity }),
            setAssignee: (assignee: ErrorTrackingIssueAssignee | null) => ({ assignee }),
            pickQuickFilter: (filter: QuickFilter, option: QuickFilterOption | null) => ({ filter, option }),
            saveFilters: true,
            clearFilters: true,
            setSaving: (saving: boolean) => ({ saving }),
        }),
        reducers({
            severity: [
                null as IssueSeverity | null,
                {
                    setSeverity: (_, { severity }) => severity,
                },
            ],
            assignee: [
                null as ErrorTrackingIssueAssignee | null,
                {
                    setAssignee: (_, { assignee }) => assignee,
                },
            ],
            saving: [
                false,
                {
                    setSaving: (_, { saving }) => saving,
                },
            ],
        }),
        selectors({
            storedFilterCount: [
                () => [(_, logicProps) => logicProps.sourceConfigs],
                (sourceConfigs: SignalSourceConfig[]): number => issueFilterCount(storedFilters(sourceConfigs)),
            ],
            payload: [
                (s) => [s.severity, s.assignee, s.filterGroup],
                (
                    severity: IssueSeverity | null,
                    assignee: ErrorTrackingIssueAssignee | null,
                    filterGroup: UniversalFiltersGroup
                ): IssueFilterPayload => issueFilterPayloadFromDraft({ severity, assignee, filterGroup }),
            ],
            saveDisabledReason: [
                (s) => [s.payload, s.saving],
                (payload: IssueFilterPayload, saving: boolean): string | null =>
                    saving ? 'Saving' : 'error' in payload ? payload.error : null,
            ],
            quickFilterSelections: [
                (s) => [s.quickFilters, s.filterGroup],
                (quickFilters: QuickFilter[], filterGroup: UniversalFiltersGroup): Record<string, string | null> =>
                    Object.fromEntries(
                        quickFilters.map((filter) => [filter.id, selectedOptionId(filterGroup, filter)])
                    ),
            ],
        }),
        listeners(({ actions, values, props: logicProps }) => {
            // Every row gets its turn even after one fails, so a failure leaves the fewest rows
            // behind. A retry writes the same filter to all of them, so a partial save heals.
            const writeEveryRow = async (body: PatchedSignalSourceConfigApi, selectedCount: number): Promise<void> => {
                if (values.currentTeamId === null) {
                    lemonToast.error('Select a project before saving')
                    return
                }
                actions.setSaving(true)
                let firstError: unknown = null
                for (const sourceConfig of logicProps.sourceConfigs) {
                    try {
                        const updated = await signalsSourceConfigsPartialUpdate(
                            String(values.currentTeamId),
                            sourceConfig.id,
                            body
                        )
                        actions.replaceSourceConfig({
                            ...sourceConfig,
                            config: updated.config ?? sourceConfig.config,
                            updated_at: updated.updated_at,
                        })
                    } catch (error) {
                        firstError = firstError ?? error
                    }
                }
                captureSignalSourceFiltersChanged({
                    sourceProduct: logicProps.sourceConfigs[0].source_product,
                    sourceType: logicProps.sourceConfigs
                        .map((config) => config.source_type)
                        .sort()
                        .join(','),
                    filter: SOURCE_ISSUE_FILTERS_KEY,
                    selectedCount,
                    success: firstError === null,
                })
                actions.setSaving(false)
                actions.loadSourceConfigs()
                if (firstError !== null) {
                    const apiError = firstError instanceof ApiError ? firstError : null
                    lemonToast.error(
                        apiError?.detail ??
                            "Couldn't save your filters for every error tracking signal type. Please try again."
                    )
                    return
                }
                lemonToast.success(
                    selectedCount > 0
                        ? 'Filters saved. They apply to new error tracking signals.'
                        : 'Filters cleared. Every new error tracking issue can reach your inbox.'
                )
                logicProps.onClose()
            }
            return {
                pickQuickFilter: ({ filter, option }) => {
                    actions.setFilterGroup(
                        withQuickFilterPick(
                            values.filterGroup,
                            filter.property_name,
                            option ? { operator: option.operator, value: option.value } : null
                        )
                    )
                },
                saveFilters: async () => {
                    const payload = values.payload
                    if ('error' in payload) {
                        return
                    }
                    if (payload.properties.length === 0) {
                        await writeEveryRow({ config_remove: [SOURCE_ISSUE_FILTERS_KEY] }, 0)
                        return
                    }
                    await writeEveryRow(
                        { config_set: { [SOURCE_ISSUE_FILTERS_KEY]: { properties: payload.properties } } },
                        payload.properties.length
                    )
                },
                clearFilters: async () => {
                    await writeEveryRow({ config_remove: [SOURCE_ISSUE_FILTERS_KEY] }, 0)
                },
            }
        }),
        afterMount(({ actions, props: logicProps }) => {
            const draft = issueFilterDraftFromStored(storedFilters(logicProps.sourceConfigs))
            actions.setFilterGroup(draft.filterGroup)
            actions.setSeverity(draft.severity)
            actions.setAssignee(draft.assignee)
        }),
    ])
