import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { lemonToast } from '@posthog/lemon-ui'

import api from 'lib/api'
import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'

import { TaskRunStatus } from 'products/posthog_ai/frontend/types/taskTypes'

import type { ActiveCreation } from '../../../../../frontend/src/layout/ai/runnerPanelLogic'
import type { FeatureFlagsSet } from '../../../../../frontend/src/lib/logic/featureFlagLogic'
import { captureInboxReportAction } from '../inboxAnalytics'
import { inboxTaskKickoffLogic } from '../inboxTaskKickoffLogic'
import { SignalReport } from '../types'
import { displayConventionalCommitTitle } from '../utils/reportPresentation'

const POLL_INTERVAL_MS = 15_000
const FINISHED_STATUSES: TaskRunStatus[] = [TaskRunStatus.COMPLETED, TaskRunStatus.FAILED, TaskRunStatus.CANCELLED]

export interface WatchedRun {
    report: SignalReport
    taskId: string
    runId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface inboxRunNoticeLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    activeCreation: ActiveCreation | null // inboxTaskKickoffLogic
    watchedRuns: Record<string, WatchedRun>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface inboxRunNoticeLogicActions {
    openReportTask: (
        report: SignalReport,
        taskId: string,
        runId: string,
        streamKey?: string | undefined
    ) => {
        report: SignalReport
        runId: string
        streamKey: string | undefined
        taskId: string
    } // inboxTaskKickoffLogic
    pollWatchedRuns: () => {
        value: true
    }
    runFinished: (runId: string) => {
        runId: string
    }
}

export type inboxRunNoticeLogicType = MakeLogicType<inboxRunNoticeLogicValues, inboxRunNoticeLogicActions>

/** Lives as long as the inbox scene, so it covers this tab's session; the bell notification covers the rest. */
export const inboxRunNoticeLogic = kea<inboxRunNoticeLogicType>([
    path(['products', 'signals', 'inbox', 'logics', 'inboxRunNoticeLogic']),

    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], inboxTaskKickoffLogic, ['activeCreation']],
        actions: [inboxTaskKickoffLogic, ['openReportTask']],
    })),

    actions({
        pollWatchedRuns: true,
        runFinished: (runId: string) => ({ runId }),
    }),

    reducers({
        watchedRuns: [
            {} as Record<string, WatchedRun>,
            {
                openReportTask: (state, { report, taskId, runId }) => ({
                    ...state,
                    [runId]: { report, taskId, runId },
                }),
                runFinished: (state, { runId }) => {
                    const { [runId]: _finished, ...rest } = state
                    return rest
                },
            },
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        openReportTask: () => {
            if (!values.featureFlags[FEATURE_FLAGS.INBOX_RUN_FINISHED_NOTICES]) {
                return
            }
            cache.disposables.add(() => {
                const id = window.setInterval(actions.pollWatchedRuns, POLL_INTERVAL_MS)
                return () => window.clearInterval(id)
            }, 'pollWatchedRuns')
        },
        pollWatchedRuns: async () => {
            const watched = Object.values(values.watchedRuns)
            if (watched.length === 0) {
                cache.disposables.dispose('pollWatchedRuns')
                return
            }
            for (const { report, taskId, runId } of watched) {
                const task = await api.tasks.get(taskId).catch(() => null)
                if (cache.disposables.isDisposed) {
                    return
                }
                const run = task?.latest_run
                if (!run || run.id !== runId) {
                    // A newer run replaced this one, so this one has nothing left to report.
                    if (run) {
                        actions.runFinished(runId)
                    }
                    continue
                }
                if (!FINISHED_STATUSES.includes(run.status)) {
                    continue
                }
                actions.runFinished(runId)
                if (values.activeCreation?.runId === runId) {
                    continue
                }
                captureInboxReportAction({ report, actionType: 'run_notice_shown', surface: 'toast' })
                const title = displayConventionalCommitTitle(report.title, 'Untitled report')
                const message =
                    run.status === TaskRunStatus.COMPLETED
                        ? `The run for "${title}" finished.`
                        : `The run for "${title}" stopped before it finished.`
                const open = (): void => {
                    captureInboxReportAction({ report, actionType: 'run_notice_opened', surface: 'toast' })
                    actions.openReportTask(report, taskId, runId)
                }
                const toastOptions = {
                    toastId: `inbox-run-finished-${runId}`,
                    button: { label: 'View run', action: open },
                }
                if (run.status === TaskRunStatus.COMPLETED) {
                    lemonToast.success(message, toastOptions)
                } else {
                    lemonToast.warning(message, toastOptions)
                }
            }
        },
    })),
])
