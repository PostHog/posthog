import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { signalsReportsPrCiStatuses } from 'products/signals/frontend/generated/api'
import type { PullRequestCiStatusEnumApi } from 'products/signals/frontend/generated/api.schemas'

/** CI state per report id. A report GitHub has not answered for is simply absent. */
export type PrCiStatusMap = Record<string, PullRequestCiStatusEnumApi>

/** How often the tracked pull requests are re-read while the inbox is open. */
export const PR_CI_STATUS_POLL_INTERVAL_MS = 60_000
/** Reports one request may ask about, above which the endpoint rejects the list. */
export const PR_CI_STATUS_MAX_REPORTS = 100
/** Sections load independently, so their bursts coalesce into one request. */
const PR_CI_STATUS_DEBOUNCE_MS = 50

/**
 * Whether two announcements cover the same rows. Both lists are deduplicated, so length and
 * membership are enough, and neither list's order carries meaning.
 */
function coversSameReports(reportIds: string[], other: string[]): boolean {
    return reportIds.length === other.length && reportIds.every((reportId) => other.includes(reportId))
}

