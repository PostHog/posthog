/**
 * CI state of the implementation pull requests the report lists show, so a reader scanning the inbox
 * can see which pull requests are red without opening each report in turn.
 *
 * Shared rather than keyed: every report section paints the same pill, and the flat list merges
 * several sections, so one map serves them all and a report listed twice costs one lookup. Sections
 * announce the reports they show through `trackReports`; the backend resolves the whole set in one
 * batched GitHub read, and a poll keeps a running build's glyph moving while the inbox stays open.
 */
export const prCiStatusLogic = kea<prCiStatusLogicType>([
    path(['scenes', 'inbox', 'logics', 'prCiStatusLogic']),

    actions({
        trackReports: (source: string, reportIds: string[]) => ({ source, reportIds }),
    }),

    loaders(({ values }) => ({
        ciStatusByReportId: [
            {} as PrCiStatusMap,
            {
                loadCiStatuses: async ({ reportIds }: { reportIds: string[] }, breakpoint) => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId || reportIds.length === 0) {
                        return {}
                    }
                    const response = await signalsReportsPrCiStatuses(String(teamId), {
                        report_ids: reportIds.join(','),
                    })
                    breakpoint()
                    // Merge forward, then keep only the reports still on screen: a pull request
                    // GitHub could not answer for this time holds the state it last had instead of
                    // losing its glyph for a poll, and a report that scrolled out is forgotten.
                    const merged: PrCiStatusMap = { ...values.ciStatusByReportId }
                    for (const entry of response.statuses) {
                        merged[entry.report_id] = entry.ci_status
                    }
                    return Object.fromEntries(
                        reportIds
                            .filter((reportId) => reportId in merged)
                            .map((reportId) => [reportId, merged[reportId]])
                    )
                },
            },
        ],
    })),

    reducers({
        // Kept per announcing section, so a section that narrows its filter stops asking about rows it
        // no longer shows. Accumulating one flat set instead would keep every row a reader ever
        // scrolled past in the poll for as long as the inbox stayed open.
        trackedReportIdsBySource: [
            {} as Record<string, string[]>,
            {
                trackReports: (
                    state: Record<string, string[]>,
                    { source, reportIds }: { source: string; reportIds: string[] }
                ) => ({ ...state, [source]: reportIds }),
            },
        ],
        // What the last request covered, so a section re-rendering the same rows doesn't re-ask.
        requestedReportIds: [
            [] as string[],
            {
                loadCiStatuses: (_: string[], { reportIds }: { reportIds: string[] }) => reportIds,
            },
        ],
    }),

    selectors({
        // The cap matches the endpoint's, which rejects a longer list than it will answer for.
        trackedReportIds: [
            (s) => [s.trackedReportIdsBySource],
            (trackedReportIdsBySource: Record<string, string[]>): string[] =>
                Array.from(new Set(Object.values(trackedReportIdsBySource).flat())).slice(0, PR_CI_STATUS_MAX_REPORTS),
        ],
    }),

    listeners(({ actions, values }) => ({
        trackReports: async (_, breakpoint) => {
            // A section re-rendering the same rows must not re-ask. Any other set has to: a new row
            // has no state yet, and a row that left and came back may have gone stale while the poll
            // was not covering it. An empty set costs no request and clears the rows that left.
            if (coversSameReports(values.trackedReportIds, values.requestedReportIds)) {
                return
            }
            await breakpoint(PR_CI_STATUS_DEBOUNCE_MS)
            actions.loadCiStatuses({ reportIds: values.trackedReportIds })
        },
    })),

    afterMount(({ actions, values, cache }) => {
        // A build that goes red while someone is reading the list should show it. Auto-disposed on
        // unmount and paused on a hidden tab, so a backgrounded inbox costs GitHub nothing.
        cache.disposables.add(() => {
            const interval = setInterval(() => {
                if (values.trackedReportIds.length > 0) {
                    actions.loadCiStatuses({ reportIds: values.trackedReportIds })
                }
            }, PR_CI_STATUS_POLL_INTERVAL_MS)
            return () => clearInterval(interval)
        }, 'prCiStatusPoll')
    }),
])
