/**
 * Triage mode: one report at a time from the Needs-a-decision queue, driven from the keyboard. The
 * queue is the landing view's own `reportListLogic` (same pages, filters, and reviewer scope), so
 * archiving here drops the row from the list too and the next report slides into place.
 */
export const inboxTriageLogic = kea<inboxTriageLogicType>([
    path(['scenes', 'inbox', 'logics', 'inboxTriageLogic']),

    connect(() => ({
        values: [
            reportListLogic(TRIAGE_LIST_PROPS),
            ['reports', 'hasMore', 'isLoaded', 'reportsResponseLoading', 'reportsLoadFailed'],
            inboxTaskKickoffLogic,
            ['isCreatingPr', 'aiConsentDisabledReason'],
        ],
        actions: [
            reportListLogic(TRIAGE_LIST_PROPS),
            [
                'ensureLoaded',
                'loadMore',
                'archiveReport',
                'removeReport',
                'loadReportsSuccess',
                'loadMoreReportsSuccess',
                'loadMoreReportsFailure',
            ],
            inboxTaskKickoffLogic,
            ['createPrFromReport'],
            inboxSceneLogic,
            ['setSelectedReportId'],
        ],
    })),

    actions({
        navigate: (delta: number) => ({ delta }),
        setIndex: (index: number) => ({ index }),
        // Restore a spot carried in the triage URL: the report the user was on, and where it sat.
        focusReport: (reportId: string | null, index: number) => ({ reportId, index }),
        toggleExpanded: true,
        setExpanded: (expanded: boolean) => ({ expanded }),
        archiveCurrent: true,
        createPrForCurrent: true,
        openCurrent: true,
    }),

    reducers({
        // The index the user asked for. It can point past the end once archiving shrinks the list,
        // so `currentIndex` clamps it against what is loaded rather than trusting it directly.
        requestedIndex: [
            0,
            {
                setIndex: (_, { index }) => index,
                focusReport: (_, { index }) => index,
            },
        ],
        // The report the URL says the user is on. It wins over the index while it is still in the
        // queue, so rows archived above it don't shift the user onto a different report.
        requestedReportId: [
            null as string | null,
            {
                focusReport: (_, { reportId }) => reportId,
                setIndex: () => null,
            },
        ],
        expanded: [
            false,
            {
                toggleExpanded: (state) => !state,
                setExpanded: (_, { expanded }) => expanded,
            },
        ],
        // A page load toward the remembered spot failed. kea loaders leave `reports`/`hasMore`
        // unchanged on failure, so `isRestoringPosition` would otherwise stay true forever and hold the
        // view on a skeleton with nothing left to load. Stop restoring (fall back to the nearest loaded
        // report); reset when a new spot is requested or a page lands so a later retry can resume.
        restoreFailed: [
            false,
            {
                focusReport: () => false,
                loadReportsSuccess: () => false,
                loadMoreReportsSuccess: () => false,
                loadMoreReportsFailure: () => true,
            },
        ],
    }),

    selectors({
        requestedReportIndex: [
            (s) => [s.requestedReportId, s.reports],
            (requestedReportId: string | null, reports: SignalReport[]): number =>
                requestedReportId ? reports.findIndex((report) => report.id === requestedReportId) : -1,
        ],
        currentIndex: [
            (s) => [s.requestedReportIndex, s.requestedIndex, s.reports],
            (requestedReportIndex: number, requestedIndex: number, reports: SignalReport[]): number =>
                requestedReportIndex >= 0 ? requestedReportIndex : clampIndex(requestedIndex, reports.length),
        ],
        // The remembered spot sits past the loaded pages while more exist: the view waits instead of
        // flashing whichever report happens to be last on the loaded page.
        isRestoringPosition: [
            (s) => [s.requestedReportIndex, s.requestedIndex, s.reports, s.hasMore, s.restoreFailed],
            (
                requestedReportIndex: number,
                requestedIndex: number,
                reports: SignalReport[],
                hasMore: boolean,
                restoreFailed: boolean
            ): boolean => requestedReportIndex < 0 && requestedIndex >= reports.length && hasMore && !restoreFailed,
        ],
        currentReport: [
            (s) => [s.reports, s.currentIndex],
            (reports: SignalReport[], currentIndex: number): SignalReport | null => reports[currentIndex] ?? null,
        ],
        previousReport: [
            (s) => [s.reports, s.currentIndex],
            (reports: SignalReport[], currentIndex: number): SignalReport | null =>
                currentIndex > 0 ? (reports[currentIndex - 1] ?? null) : null,
        ],
        nextReport: [
            (s) => [s.reports, s.currentIndex],
            (reports: SignalReport[], currentIndex: number): SignalReport | null => reports[currentIndex + 1] ?? null,
        ],
        // "3 / 12", or "3 / 12+" while more pages are still on the server.
        counter: [
            (s) => [s.reports, s.currentIndex, s.hasMore],
            (reports: SignalReport[], currentIndex: number, hasMore: boolean): string =>
                reports.length === 0 ? '0 / 0' : `${currentIndex + 1} / ${reports.length}${hasMore ? '+' : ''}`,
        ],
        canCreatePr: [
            (s) => [s.currentReport],
            (currentReport: SignalReport | null): boolean =>
                currentReport !== null && canCreateImplementationPr(currentReport),
        ],
        // The triage URL for the current spot; what a report opened from here returns to.
        returnUrl: [
            (s) => [s.currentReport, s.currentIndex],
            (currentReport: SignalReport | null, currentIndex: number): string =>
                currentReport
                    ? combineUrl(urls.inboxTriage(), { report: currentReport.id, at: currentIndex }).url
                    : urls.inboxTriage(),
        ],
        currentReportUrl: [
            (s) => [s.currentReport, s.returnUrl],
            (currentReport: SignalReport | null, returnUrl: string): string | null =>
                currentReport
                    ? combineUrl(urls.inboxReport('reports', currentReport.id), { back: returnUrl }).url
                    : null,
        ],
    }),

    listeners(({ actions, values }) => {
        // Keep paging until the remembered spot is loaded (or the queue runs out).
        const loadTowardRequestedSpot = (): void => {
            if (values.isRestoringPosition && !values.reportsResponseLoading) {
                actions.loadMore()
            }
        }
        return {
            loadReportsSuccess: loadTowardRequestedSpot,
            loadMoreReportsSuccess: loadTowardRequestedSpot,
            navigate: ({ delta }) => {
                actions.setIndex(clampIndex(values.currentIndex + delta, values.reports.length))
                if (
                    values.hasMore &&
                    !values.reportsResponseLoading &&
                    values.currentIndex >= values.reports.length - PREFETCH_THRESHOLD
                ) {
                    actions.loadMore()
                }
            },
            archiveCurrent: () => {
                const report = values.currentReport
                if (!report) {
                    return
                }
                openDismissReportDialog({
                    reportTitle: displayConventionalCommitTitle(report.title, 'Untitled report'),
                    onConfirm: ({ reason, note }) => {
                        // The structured reason plus the user's note, matching the list-card archive
                        // path so the dismiss analytics read the same from every surface.
                        captureInboxReportAction({
                            report,
                            actionType: 'dismiss',
                            surface: 'triage_mode',
                            extra: { dismissal_reason: reason, ...(note ? { dismissal_note: note } : {}) },
                        })
                        // The list logic drops the row optimistically, so the next report takes this index.
                        actions.archiveReport(report.id, reason, note)
                    },
                })
            },
            createPrForCurrent: () => {
                const report = values.currentReport
                if (!report || !values.canCreatePr || values.isCreatingPr || values.aiConsentDisabledReason) {
                    return
                }
                captureInboxReportAction({ report, actionType: 'create_pr', surface: 'triage_mode' })
                actions.createPrFromReport(report)
            },
            openCurrent: () => {
                const report = values.currentReport
                if (report) {
                    actions.setSelectedReportId(report.id, 'triage')
                }
            },
        }
    }),

    // The URL follows the current spot (replaced, not pushed, so the browser's back button leaves
    // triage in one step). Archiving moves the spot too, once the row is gone from the list.
    actionToUrl(({ values }) => {
        const positionUrl = (): [string, Record<string, unknown>, Record<string, unknown>, { replace: boolean }] => {
            // Other params (the list scope, for one) stay; only the spot is rewritten.
            const { report: _report, at: _at, ...rest } = router.values.searchParams
            return [
                urls.inboxTriage(),
                values.currentReport ? { ...rest, report: values.currentReport.id, at: values.currentIndex } : rest,
                router.values.hashParams,
                { replace: true },
            ]
        }
        return {
            setIndex: positionUrl,
            removeReport: positionUrl,
        }
    }),

    urlToAction(({ actions }) => ({
        [urls.inboxTriage()]: (_, searchParams) => {
            const reportId = typeof searchParams.report === 'string' ? searchParams.report : null
            const at = Number(searchParams.at)
            if (reportId !== null || Number.isFinite(at)) {
                actions.focusReport(reportId, Number.isFinite(at) ? Math.max(0, Math.floor(at)) : 0)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.ensureLoaded()
    }),
])
