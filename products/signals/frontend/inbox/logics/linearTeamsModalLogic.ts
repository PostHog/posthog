/**
 * The form behind the Linear teams modal. Saving goes through `signalSourcesLogic.toggleSignalSource`,
 * which already decides between creating the row and updating it, reloads the list, and reports
 * the connection, so the enable flow and the Filters button share one save path.
 */
export const linearTeamsModalLogic: LogicWrapper<linearTeamsModalLogicType> = kea<linearTeamsModalLogicType>([
    path(['scenes', 'inbox', 'logics', 'linearTeamsModalLogic']),
    props({} as LinearTeamsModalLogicProps),
    // Not keyed on the row id: the enable flow creates the row mid-save, and a keyed instance would
    // be swapped out before its own result arrives.
    actions({
        saveSettled: true,
    }),
    reducers({
        // Set while this modal's own save is in flight, so a Linear toggle from elsewhere is ignored.
        saveInFlight: [
            false,
            {
                submitLinearTeamsRequest: () => true,
                saveSettled: () => false,
            },
        ],
    }),
    connect(() => ({
        values: [
            signalSourcesLogic,
            ['sourceConfigs', 'isLinearIssuesToggling', 'dataWarehouseSources'],
            integrationsLogic,
            ['linearIntegrations', 'integrations'],
        ],
        actions: [signalSourcesLogic, ['toggleSignalSource', 'toggleSignalSourceSuccess', 'toggleSignalSourceFailure']],
    })),
    forms(({ props: logicProps, actions, values }) => ({
        linearTeams: {
            defaults: formDefaults(logicProps.config),
            // The message hangs off `scope` (a string field) because kea-forms types an array
            // field's error as an array, one entry per item, and this is about the list as a whole.
            errors: ({ scope, teamIds }: LinearTeamsFormValues) => ({
                scope:
                    scope === 'selected' && teamIds.length === 0
                        ? 'Pick at least one team, or read all teams.'
                        : undefined,
            }),
            submit: ({ scope, teamIds }: LinearTeamsFormValues) => {
                // The endpoint replaces the config object wholesale, so the whole blob goes back with
                // the team list merged in; a partial object would clobber the steering text. The merge
                // base is the freshest cached row rather than the open-time prop snapshot.
                const baseConfig =
                    (logicProps.config &&
                        values.sourceConfigs?.find((c: SignalSourceConfig) => c.id === logicProps.config?.id)
                            ?.config) ??
                    logicProps.config?.config ??
                    {}
                actions.toggleSignalSource({
                    sourceProduct: SignalSourceProduct.Linear,
                    sourceType: SignalSourceType.Issue,
                    enabled: logicProps.enableOnSave ? true : (logicProps.config?.enabled ?? true),
                    config: { ...baseConfig, [SOURCE_LINEAR_TEAM_IDS_KEY]: scope === 'all' ? [] : teamIds },
                    viaSetupWizard: logicProps.viaSetupWizard,
                })
            },
        },
    })),
    selectors({
        // The warehouse source records the workspace it syncs, so the teams come from that connection
        // and match the synced issues. Before a source exists, any Linear connection will do.
        linearIntegration: [
            (s) => [s.linearIntegrations, s.dataWarehouseSources],
            (
                linearIntegrations: IntegrationType[],
                dataWarehouseSources: PaginatedResponse<ExternalDataSource> | null
            ): IntegrationType | null => {
                const syncedIntegrationId = dataWarehouseSources?.results.find(
                    (source: ExternalDataSource) => source.source_type === 'Linear'
                )?.job_inputs?.linear_integration_id
                return (
                    linearIntegrations.find((integration) => String(integration.id) === String(syncedIntegrationId)) ??
                    linearIntegrations[0] ??
                    null
                )
            },
        ],
        // A null list means the first load has not landed, which is not the same as no connection.
        // Reading the list rather than the loading flag keeps a later reload from blanking the picker.
        integrationsUnknown: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): boolean => integrations === null,
        ],
    }),
    listeners(({ props: logicProps, actions, values }) => ({
        toggleSignalSourceSuccess: ({ params }) => {
            if (!isLinearIssueToggle(params) || !values.saveInFlight) {
                return
            }
            actions.saveSettled()
            const teamCount = linearTeamIdsFromConfig(params.config).length
            captureSignalSourceFiltersChanged({
                sourceProduct: params.sourceProduct,
                sourceType: params.sourceType,
                filter: SOURCE_LINEAR_TEAM_IDS_KEY,
                selectedCount: teamCount,
                success: true,
            })
            lemonToast.success(
                teamCount === 0
                    ? 'Linear reads all teams from the next sync.'
                    : `Linear reads ${teamCount} ${teamCount === 1 ? 'team' : 'teams'} from the next sync.`
            )
            logicProps.onClose()
        },
        // signalSourcesLogic already shows the error toast; the modal stays open for a retry.
        toggleSignalSourceFailure: ({ params }) => {
            if (!isLinearIssueToggle(params) || !values.saveInFlight) {
                return
            }
            actions.saveSettled()
            captureSignalSourceFiltersChanged({
                sourceProduct: params.sourceProduct,
                sourceType: params.sourceType,
                filter: SOURCE_LINEAR_TEAM_IDS_KEY,
                selectedCount: linearTeamIdsFromConfig(params.config).length,
                success: false,
            })
        },
    })),
])
