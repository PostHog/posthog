/**
 * One report page: a live observation series plus the fix lifecycle. PostHog AI
 * writes the change (generating, proposed) or an external coding agent does
 * (sent, committed), and either path can be launched behind the flag. All mock,
 * nothing is created.
 */
export const v2ReportLogic: LogicWrapper<v2ReportLogicType> = kea<v2ReportLogicType>([
    props({} as V2ReportLogicProps),
    key(({ id }) => id),
    path((key) => ['products', 'signals', 'frontend', 'v2', 'v2ReportLogic', key]),
    actions({
        startGeneration: true,
        advanceGeneration: true,
        markProposed: true,
        sendToAgent: (agentName: string) => ({ agentName }),
        markCommitted: true,
        launch: true,
        setPrModalOpen: (prModalOpen: boolean) => ({ prModalOpen }),
        toggleCode: true,
        toggleEvidence: true,
        tickObservation: true,
    }),
    reducers(({ props }) => ({
        phase: [
            (contentFor(props.id)?.fix?.initialPhase ?? 'reported') as ReportFixPhase,
            {
                startGeneration: (): ReportFixPhase => 'generating',
                markProposed: (): ReportFixPhase => 'proposed',
                sendToAgent: (): ReportFixPhase => 'sent',
                markCommitted: (): ReportFixPhase => 'committed',
                launch: (): ReportFixPhase => 'launched',
            },
        ],
        generationStep: [
            0,
            {
                startGeneration: () => 0,
                advanceGeneration: (state) => state + 1,
            },
        ],
        agentName: [
            null as string | null,
            {
                sendToAgent: (_, { agentName }) => agentName,
            },
        ],
        prModalOpen: [
            false,
            {
                setPrModalOpen: (_, { prModalOpen }) => prModalOpen,
                startGeneration: () => false,
            },
        ],
        codeOpen: [
            false,
            {
                toggleCode: (state) => !state,
            },
        ],
        evidenceExpanded: [
            false,
            {
                toggleEvidence: (state) => !state,
            },
        ],
        livePoints: [
            (contentFor(props.id)?.observation.chart.series ?? []).map((series) => [...series.points]),
            {
                // Slide the window one point per tick, so the chart reads as time passing.
                tickObservation: (state) => {
                    const liveRange = contentFor(props.id)?.observation.liveRange ?? [0, 1]
                    return state.map((points, seriesIndex) => {
                        const last = points[points.length - 1] ?? 0
                        const next =
                            seriesIndex === 0
                                ? nextPrimaryPoint(last, liveRange[0], liveRange[1])
                                : nextSecondaryPoint(last)
                        return [...points.slice(1), next]
                    })
                },
            },
        ],
        observationTicks: [
            0,
            {
                tickObservation: (state) => state + 1,
            },
        ],
    })),
    selectors(({ props }) => ({
        report: [() => [], (): DemoReport | null => getDemoReport(props.id)],
        content: [(s) => [s.report], (report: DemoReport | null): DemoReportContent | null => report?.content ?? null],
        generationSteps: [
            (s) => [s.content],
            (content: DemoReportContent | null): string[] => content?.fix?.generationSteps ?? [],
        ],
        monitoringCriteria: [
            (s) => [s.content],
            (content: DemoReportContent | null): string[] =>
                (content?.fix?.monitoringCriteria ?? '')
                    .split(',')
                    .map((criterion) => criterion.trim())
                    .filter(Boolean),
        ],
        changeStats: [
            (s) => [s.content],
            (content: DemoReportContent | null): ReportChangeStats => countDiffLines(content?.fix?.changes ?? []),
        ],
        observationChart: [
            (s) => [s.content, s.livePoints, s.observationTicks],
            (content: DemoReportContent | null, livePoints: number[][], observationTicks: number): DemoChartData => {
                if (!content) {
                    return { series: [], pointLabels: [], xLabels: [] }
                }
                const chart = content.observation.chart
                const series = chart.series.map((entry, index) => ({
                    ...entry,
                    points: livePoints[index] ?? entry.points,
                }))
                return {
                    ...chart,
                    series,
                    pointLabels: hourlyPointLabels(series[0]?.points.length ?? 0),
                    // Annotations are pinned to point indexes, so they drift left as the window slides.
                    annotations: chart.annotations
                        ?.map((annotation) => ({ ...annotation, index: annotation.index - observationTicks }))
                        .filter((annotation) => annotation.index >= 0),
                }
            },
        ],
        observationValue: [
            (s) => [s.livePoints],
            (livePoints: number[][]): string => {
                const primary = livePoints[0]
                const latest = primary?.[primary.length - 1]
                return latest === undefined ? '' : Math.round(latest).toLocaleString()
            },
        ],
        timeline: [
            (s) => [s.content, s.phase, s.agentName],
            (
                content: DemoReportContent | null,
                phase: ReportFixPhase,
                agentName: string | null
            ): ReportTimelineEntry[] => {
                const rows = [...(content?.timeline ?? [])]
                const fix = content?.fix
                if (!fix) {
                    return rows
                }
                if (fix.initialPhase === 'launched') {
                    // The content timeline already tells the shipped-fix story.
                    return rows
                }
                if (agentName) {
                    rows.push({
                        label: `Handed off to ${agentName}`,
                        time: 'just now',
                        chip: 'context',
                        color: 'muted',
                    })
                } else if (['generating', 'proposed', 'launched'].includes(phase)) {
                    rows.push({
                        label: 'Code change generated for review',
                        time: 'just now',
                        chip: 'opus',
                        color: 'muted',
                    })
                }
                if (agentName && ['committed', 'launched'].includes(phase)) {
                    rows.push({
                        label: `Commit detected on ${fix.branch}`,
                        time: 'just now',
                        chip: DEMO_COMMIT_SHA,
                        color: 'success',
                    })
                }
                if (phase === 'launched') {
                    rows.push({
                        label: 'Launched behind the flag, monitoring',
                        time: 'just now',
                        chip: 'live',
                        color: 'success',
                    })
                }
                return rows
            },
        ],
    })),
    listeners(({ actions, values, cache }) => ({
        startGeneration: () => {
            cache.disposables.add(() => {
                const timer = window.setInterval(() => actions.advanceGeneration(), GENERATION_TICK_MS)
                return () => clearInterval(timer)
            }, 'generation')
        },
        advanceGeneration: () => {
            if (values.generationStep >= values.generationSteps.length) {
                cache.disposables.dispose('generation')
                actions.markProposed()
            }
        },
        sendToAgent: () => {
            cache.disposables.add(() => {
                const timer = window.setTimeout(() => actions.markCommitted(), COMMIT_DELAY_MS)
                return () => clearTimeout(timer)
            }, 'commit')
        },
    })),
    afterMount(({ actions, values, cache }) => {
        cache.disposables.add(() => {
            const timer = window.setInterval(() => actions.tickObservation(), OBSERVATION_TICK_MS)
            return () => clearInterval(timer)
        }, 'observation')

        // The inbox and focus pages deep-link here with #fix to start the fix flow straight away.
        if (values.content?.fix && window.location.hash === '#fix') {
            router.actions.replace(router.values.location.pathname, router.values.searchParams, {})
            actions.startGeneration()
        }
    }),
])
