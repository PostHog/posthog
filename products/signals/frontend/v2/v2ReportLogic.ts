/** Line counts shown above the generated diff. */
export interface ReportChangeStats {
    added: number
    removed: number
    files: number
}

const GENERATION_TICK_MS = 900
const COMMIT_DELAY_MS = 4500
const OBSERVATION_TICK_MS = 2000

/** No mock report carries commit or PR records, so every fix branch reports the same pair. */
export const DEMO_COMMIT_SHA = '9d2e4b7'
export const DEMO_PR_NUMBER = 4821

function contentFor(id: string): DemoReportContent | null {
    return getDemoReport(id)?.content ?? null
}

/** Bounded random walk, so the headline metric wanders without escaping its range. */
function nextPrimaryPoint(last: number, min: number, max: number): number {
    const step = (Math.random() - 0.45) * (max - min || 1) * 0.3
    return Math.min(max, Math.max(min, last + step))
}

function nextSecondaryPoint(last: number): number {
    return Math.max(0, last * (1 + (Math.random() - 0.5) * 0.16))
}

function countDiffLines(changes: ReportFixChange[]): ReportChangeStats {
    let added = 0
    let removed = 0
    for (const change of changes) {
        for (const line of change.snippet.split('\n')) {
            if (line.startsWith('+')) {
                added += 1
            } else if (line.startsWith('-')) {
                removed += 1
            }
        }
    }
    return { added, removed, files: changes.length }
}

