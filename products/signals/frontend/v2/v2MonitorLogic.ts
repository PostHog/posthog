import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
    selectors,
} from 'kea'

import { lemonToast } from '@posthog/lemon-ui'

import { hourlyPointLabels } from './mockReportContent'
import { DemoChartAnnotation, DemoChartData } from './types'

export interface V2MonitorLogicProps {
    id: string
}

/** Flag the fix on the monitor page rolls out behind. */
export const MONITOR_FLAG_KEY = 'synthetic-stack-fallback'

const RECOVERY_TICK_MS = 2000
const FRESHNESS_TICK_MS = 1000
const RAMP_TICK_MS = 300
const RAMP_STEP = 5

/** Bounds for the readings the recovery ticker appends, i.e. the post-fix floor. */
const LIVE_RANGE: [number, number] = [3, 6]

const INITIAL_RECOVERY_POINTS = [
    58, 61, 59, 63, 60, 62, 64, 61, 63, 60, 62, 59, 61, 58, 44, 31, 22, 15, 11, 8, 6, 5, 4, 4,
]

const INITIAL_ANNOTATIONS: DemoChartAnnotation[] = [{ index: 14, label: 'fix shipped', color: 'success' }]

const RECOVERY_X_LABELS = ['24h ago', '12h ago', 'now']

// Widened to `number` so kea-typegen infers the reducer values as numbers, not literals.
const BASE_TREATED_RATE: number = 3.8
const INITIAL_TREATED_SESSIONS: number = 12480
const INITIAL_CONTROL_SESSIONS: number = 12395

export interface MonitorComparisonRow {
    metric: string
    treated: string
    control: string
}

export interface MonitorSignalCheck {
    label: string
    detail: string
    met: boolean
}

export type MonitorRolloutStepState = 'done' | 'now' | 'scheduled'

export interface MonitorRolloutStep {
    label: string
    state: MonitorRolloutStepState
}

/** One reading of everything that moves on this page, so the reducers stay pure. */
export interface MonitorTick {
    /** Newest stackless-captures-per-hour point */
    capturesPerHour: number
    /** Offset applied to the treated capture rate, within ±0.3 */
    rateDrift: number
    treatedSessions: number
    controlSessions: number
}

function randomBetween(min: number, max: number): number {
    return min + Math.random() * (max - min)
}

function oneDecimal(value: number): number {
    return Math.round(value * 10) / 10
}

function nextTick(): MonitorTick {
    return {
        capturesPerHour: oneDecimal(randomBetween(LIVE_RANGE[0], LIVE_RANGE[1])),
        rateDrift: randomBetween(-0.3, 0.3),
        treatedSessions: Math.round(randomBetween(10, 40)),
        controlSessions: Math.round(randomBetween(10, 40)),
    }
}

