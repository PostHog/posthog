/**
 * Live state for the mock-data fix monitor: a sliding recovery window, a drifting
 * treated-vs-control comparison, and a flag ramp the demo can actually run.
 * Nothing here talks to the backend.
 */
export const v2MonitorLogic: LogicWrapper<v2MonitorLogicType> = kea<v2MonitorLogicType>([
    props({} as V2MonitorLogicProps),
    key(({ id }) => id),
    path((key) => ['products', 'signals', 'frontend', 'v2', 'v2MonitorLogic', key]),
    actions({
        tick: (sample: MonitorTick) => ({ sample }),
        tickFreshness: true,
        startRamp: true,
        advanceRamp: true,
        finishRamp: true,
    }),
    reducers({
        recoveryPoints: [
            INITIAL_RECOVERY_POINTS,
            {
                tick: (state, { sample }) => [...state.slice(1), sample.capturesPerHour],
            },
        ],
        recoveryAnnotations: [
            INITIAL_ANNOTATIONS,
            {
                // The window slides one point per tick, so markers walk left and eventually fall off it.
                tick: (state) =>
                    state
                        .map((annotation) => ({ ...annotation, index: annotation.index - 1 }))
                        .filter((annotation) => annotation.index >= 0),
            },
        ],
        treatedRate: [
            BASE_TREATED_RATE,
            {
                tick: (_, { sample }) => oneDecimal(BASE_TREATED_RATE + sample.rateDrift),
            },
        ],
        treatedSessions: [
            INITIAL_TREATED_SESSIONS,
            {
                tick: (state, { sample }) => state + sample.treatedSessions,
            },
        ],
        controlSessions: [
            INITIAL_CONTROL_SESSIONS,
            {
                tick: (state, { sample }) => state + sample.controlSessions,
            },
        ],
        secondsSinceCheck: [
            0,
            {
                tickFreshness: (state) => state + 1,
                tick: () => 0,
            },
        ],
        rolloutPercent: [
            50,
            {
                advanceRamp: (state) => Math.min(100, state + RAMP_STEP),
            },
        ],
        ramping: [
            false,
            {
                startRamp: () => true,
                finishRamp: () => false,
            },
        ],
    }),
    selectors({
        recoveryChart: [
            (s) => [s.recoveryPoints, s.recoveryAnnotations],
            (recoveryPoints: number[], recoveryAnnotations: DemoChartAnnotation[]): DemoChartData => ({
                series: [{ name: 'Stackless captures per hour', color: 'accent', points: recoveryPoints }],
                pointLabels: hourlyPointLabels(recoveryPoints.length),
                xLabels: RECOVERY_X_LABELS,
                unit: 'per hour',
                baselineValue: 5,
                baselineLabel: 'target under 5/hr',
                annotations: recoveryAnnotations,
            }),
        ],
        comparisonRows: [
            (s) => [s.treatedRate, s.treatedSessions, s.controlSessions],
            (treatedRate: number, treatedSessions: number, controlSessions: number): MonitorComparisonRow[] => [
                { metric: 'Stackless captures per hour', treated: treatedRate.toFixed(1), control: '61.2' },
                { metric: 'Distinct issues created per day', treated: '14', control: '1' },
                { metric: 'Median events per new issue', treated: '9', control: '3,412' },
                {
                    metric: 'Sessions observed',
                    treated: treatedSessions.toLocaleString(),
                    control: controlSessions.toLocaleString(),
                },
            ],
        ],
        signalChecks: [
            (s) => [s.treatedRate],
            (treatedRate: number): MonitorSignalCheck[] => [
                {
                    label: 'Stackless captures under 5 per hour',
                    detail: `${treatedRate.toFixed(1)}/hr right now`,
                    met: true,
                },
                {
                    label: 'No regrouping churn on existing issues',
                    detail: 'hashes on existing issues unchanged',
                    met: true,
                },
                {
                    label: 'New tickets about untriageable errors: 0 since the fix',
                    detail: 'support queue checked hourly',
                    met: true,
                },
                { label: 'Holds for 7 days', detail: 'day 1 of 7', met: false },
            ],
        ],
        rampComplete: [(s) => [s.rolloutPercent], (rolloutPercent: number): boolean => rolloutPercent >= 100],
        rolloutSteps: [
            (s) => [s.rampComplete],
            (rampComplete: boolean): MonitorRolloutStep[] => [
                { label: '10% · Aug 20 01:30', state: 'done' },
                { label: '50% · Aug 20 06:00', state: rampComplete ? 'done' : 'now' },
                { label: '100%', state: rampComplete ? 'now' : 'scheduled' },
            ],
        ],
        freshnessLabel: [
            (s) => [s.secondsSinceCheck],
            (secondsSinceCheck: number): string => `checked ${secondsSinceCheck}s ago`,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        startRamp: () => {
            cache.disposables.add(() => {
                const timer = window.setInterval(() => actions.advanceRamp(), RAMP_TICK_MS)
                return () => clearInterval(timer)
            }, 'ramp')
        },
        advanceRamp: () => {
            if (values.rolloutPercent < 100) {
                return
            }
            cache.disposables.dispose('ramp')
            actions.finishRamp()
            lemonToast.success('Rollout ramped to 100%')
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.disposables.add(() => {
            const timer = window.setInterval(() => actions.tick(nextTick()), RECOVERY_TICK_MS)
            return () => clearInterval(timer)
        }, 'recovery')
        cache.disposables.add(() => {
            const timer = window.setInterval(() => actions.tickFreshness(), FRESHNESS_TICK_MS)
            return () => clearInterval(timer)
        }, 'freshness')
    }),
])
