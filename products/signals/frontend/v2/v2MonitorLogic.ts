    recoveryAnnotations: DemoChartAnnotation[]
    recoveryChart: DemoChartData
    recoveryPoints: number[]
    rolloutPercent: number
    rolloutSteps: MonitorRolloutStep[]
    secondsSinceCheck: number
    signalChecks: MonitorSignalCheck[]
    treatedRate: number
