import { MakeLogicType, actions, kea, key, listeners, path, props, reducers, selectors } from 'kea'

import { getDemoReport } from '../mockData'
import { DemoReport } from '../types'

export interface ReportChatMessage {
    id: number
    role: 'user' | 'assistant'
    text: string
}

export interface ReportChatLogicProps {
    id: string
}

/** Canned answers keyed by a word in the question; the last entry is the fallback. */
function mockReply(question: string, report: DemoReport): string {
    const q = question.toLowerCase()
    const content = report.content
    if (q.includes('fix') || q.includes('change')) {
        return content?.fix
            ? `${content.fix.summary} The change ships behind the \`${content.fix.flagKey}\` flag, so you can roll it back without a deploy.`
            : 'This report has no proposed fix yet. I can draft one once the investigation finishes.'
    }
    if (q.includes('impact') || q.includes('how many') || q.includes('users')) {
        const tiles = content?.impactTiles.map((tile) => `${tile.value} ${tile.label}`).join(', ')
        return tiles
            ? `Current impact: ${tiles}. The trend is ${report.trend === 'up' ? 'still growing' : report.trend === 'down' ? 'recovering' : 'flat'}.`
            : `The headline impact is ${report.impact}.`
    }
    if (q.includes('cause') || q.includes('why') || q.includes('happen')) {
        return content?.howWeKnow.length
            ? `${content.howWeKnow[0]} ${content.howWeKnow[1] ?? ''}`.trim()
            : report.verdict
    }
    if (q.includes('evidence') || q.includes('source') || q.includes('proof')) {
        return `This report is built from ${report.proof}. Sources: ${report.sources.join(', ')}.`
    }
    return `${report.verdict} Ask me about the cause, the impact, the evidence, or the proposed fix.`
}

