// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reportChatLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        suggestedQuestions: (report: DemoReport | null) => string[]
    }
}

export type reportChatLogicType = MakeLogicType<
    reportChatLogicValues,
    reportChatLogicActions,
    ReportChatLogicProps,
    reportChatLogicMeta
>

export const reportChatLogic = kea<reportChatLogicType>([
    props({} as ReportChatLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'signals', 'frontend', 'v2', 'components', 'reportChatLogic', key]),
    actions({
        setDraft: (draft: string) => ({ draft }),
        sendMessage: true,
        addMessage: (message: ReportChatMessage) => ({ message }),
        setReplying: (replying: boolean) => ({ replying }),
    }),
    reducers({
        draft: [
            '',
            {
                setDraft: (_, { draft }) => draft,
            },
        ],
        messages: [
            [] as ReportChatMessage[],
            {
                addMessage: (state, { message }) => [...state, message],
            },
        ],
        replying: [
            false,
            {
                setReplying: (_, { replying }) => replying,
            },
        ],
    }),
    selectors(({ props }) => ({
        report: [() => [], (): DemoReport | null => getDemoReport(props.id)],
        suggestedQuestions: [
            (s) => [s.report],
            (report: DemoReport | null): string[] =>
                report?.content?.fix
                    ? ['What caused this?', 'Who is affected?', 'Walk me through the fix']
                    : ['What caused this?', 'Who is affected?', 'What evidence backs this up?'],
        ],
    })),
    listeners(({ actions, values }) => ({
        sendMessage: async (_, breakpoint) => {
            const text = values.draft.trim()
            if (!text || values.replying || !values.report) {
                return
            }
            actions.addMessage({ id: values.messages.length + 1, role: 'user', text })
            actions.setDraft('')
            actions.setReplying(true)
            await breakpoint(900)
            actions.addMessage({
                id: values.messages.length + 1,
                role: 'assistant',
                text: mockReply(text, values.report),
            })
            actions.setReplying(false)
        },
    })),
])
