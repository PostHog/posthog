export type v2InboxLogicType = MakeLogicType<
    v2InboxLogicValues,
    v2InboxLogicActions,
    Record<string, any>,
    v2InboxLogicMeta
>

/** Mock-data state for the inbox v2 redesign preview. Nothing here talks to the backend. */
export const v2InboxLogic = kea<v2InboxLogicType>([
    path(['products', 'signals', 'frontend', 'v2', 'v2InboxLogic']),
    actions({
        setFilter: (filter: InboxDemoFilter) => ({ filter }),
        setSort: (sort: InboxDemoSort) => ({ sort }),
        toggleRowExpanded: (id: string) => ({ id }),
        openPrModal: (target: InboxPrModalTarget) => ({ target }),
        closePrModal: true,
        confirmPrModal: true,
        tickLiveActivity: true,
    }),
    reducers({
        filter: ['all' as InboxDemoFilter, { setFilter: (_, { filter }) => filter }],
        sort: ['impact' as InboxDemoSort, { setSort: (_, { sort }) => sort }],
        expandedRowId: [
            null as string | null,
            { toggleRowExpanded: (current, { id }) => (current === id ? null : id) },
        ],
        prModalTarget: [
            null as InboxPrModalTarget | null,
            {
                openPrModal: (_, { target }) => target,
                closePrModal: () => null,
            },
        ],
        liveActivityIndex: [0, { tickLiveActivity: (index) => index + 1 }],
    }),
    selectors({
        filteredReports: [
            (s) => [s.filter, s.sort],
            (filter: InboxDemoFilter, sort: InboxDemoSort): DemoReport[] =>
                DEMO_REPORTS.filter((report) => matchesFilter(report, filter)).sort((a, b) =>
                    sort === 'recency' ? a.ageHours - b.ageHours : b.impactWeight - a.impactWeight
                ),
        ],
        liveActivityPhrase: [
            (s) => [s.liveActivityIndex],
            (index: number): string => LIVE_ACTIVITY_PHRASES[index % LIVE_ACTIVITY_PHRASES.length],
        ],
    }),
    listeners(({ values }) => ({
        confirmPrModal: () => {
            // The report page reads the `#fix` hash and starts its fix flow on arrival.
            if (values.prModalTarget) {
                router.actions.push(`${urls.v2Report(values.prModalTarget.reportId)}#fix`)
            }
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.disposables.add(() => {
            const timer = window.setInterval(() => actions.tickLiveActivity(), LIVE_ACTIVITY_INTERVAL_MS)
            return () => clearInterval(timer)
        })
    }),
])
