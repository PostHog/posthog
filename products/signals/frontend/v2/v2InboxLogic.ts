import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'

import { urls } from 'scenes/urls'

import { DEMO_REPORTS, LIVE_ACTIVITY_PHRASES } from './mockData'
import { DemoReport, InboxDemoFilter, InboxDemoSort } from './types'

export interface InboxPrModalTarget {
    reportId: string
    flagKey: string
}

const LIVE_ACTIVITY_INTERVAL_MS = 1700

function matchesFilter(report: DemoReport, filter: InboxDemoFilter): boolean {
    switch (filter) {
        case 'attention':
            return !!report.unread || !!report.live || report.trend === 'up'
        case 'open':
            return report.status !== 'Resolved' && report.status !== 'Dismissed'
        case 'monitoring':
            return report.status === 'Verifying'
        case 'archived':
            return ['Resolved', 'Dismissed', 'Disputed'].includes(report.status)
        case 'all':
            return true
    }
}

