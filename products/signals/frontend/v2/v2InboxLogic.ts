export interface InboxPrModalTarget {
    reportId: string
    flagKey: string
}

function matchesFilter(report: DemoReport, filter: InboxDemoFilter): boolean {
    switch (filter) {
        case 'open':
            return report.status !== 'Resolved' && report.status !== 'Dismissed'
        case 'monitoring':
            return report.status === 'Verifying'
        case 'archived':
            return ['Resolved', 'Dismissed', 'Disputed'].includes(report.status)
        case 'all':
            return true
    }
}

/** Rows a grouped section shows before "Show more"; each click reveals another page. */
export const GROUP_PAGE_SIZE = 5

export interface InboxReportGroup {
    key: InboxDemoGroup
    label: string
    reports: DemoReport[]
}

function groupFor(report: DemoReport): InboxDemoGroup {
    switch (report.status) {
        case 'New':
        case 'Viewed':
            return 'decision'
        case 'Resolved':
        case 'Dismissed':
            return 'resolved'
        default:
            return 'monitoring'
    }
}

function compareReports(sort: InboxDemoSort): (a: DemoReport, b: DemoReport) => number {
    return sort === 'recency' ? (a, b) => a.ageHours - b.ageHours : (a, b) => b.impactWeight - a.impactWeight
}

/** Distinct product areas across the mock reports, in first-seen order. */
export const DEMO_PRODUCT_OPTIONS: string[] = Array.from(new Set(DEMO_REPORTS.map((report) => report.area)))

/** Mock area tags are uppercase mono ("FEATURE FLAGS"); menus and settings show them as "Feature flags". */
export function productLabel(area: string): string {
    const lower = area.toLowerCase()
    return lower.charAt(0).toUpperCase() + lower.slice(1)
}

export const PRODUCT_OPTIONS: { value: string | null; label: string }[] = [
    { value: null, label: 'All products' },
    ...DEMO_PRODUCT_OPTIONS.map((area) => ({ value: area, label: productLabel(area) })),
]

