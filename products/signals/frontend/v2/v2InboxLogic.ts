/** Mock-data state for the inbox v2 redesign preview. Nothing here talks to the backend. */
export const v2InboxLogic = kea<v2InboxLogicType>([
    path(['products', 'signals', 'frontend', 'v2', 'v2InboxLogic']),
    actions({
        setTab: (tab: InboxDemoTab) => ({ tab }),
        setFilter: (filter: InboxDemoFilter) => ({ filter }),
        setLayout: (layout: InboxDemoLayout) => ({ layout }),
        setSort: (sort: InboxDemoSort) => ({ sort }),
        showMoreInGroup: (group: InboxDemoGroup) => ({ group }),
        toggleGroupOpen: (group: InboxDemoGroup) => ({ group }),
        setProductFilter: (product: string | null) => ({ product }),
        setScope: (scope: InboxDemoScope) => ({ scope }),
        toggleRowExpanded: (id: string) => ({ id }),
        openPrModal: (target: InboxPrModalTarget) => ({ target }),
        closePrModal: true,
        confirmPrModal: true,
        toggleSetting: (key: string) => ({ key }),
        toggleAssignedProduct: (area: string) => ({ area }),
    }),
    reducers({
        activeTab: ['reports' as InboxDemoTab, { setTab: (_, { tab }) => tab }],
        filter: ['all' as InboxDemoFilter, { setFilter: (_, { filter }) => filter }],
        layout: ['grouped' as InboxDemoLayout, { setLayout: (_, { layout }) => layout }],
        sort: ['users' as InboxDemoSort, { setSort: (_, { sort }) => sort }],
        visibleGroupCounts: [
            {} as Record<string, number>,
            {
                showMoreInGroup: (state, { group }) => ({
                    ...state,
                    [group]: (state[group] ?? GROUP_PAGE_SIZE) + GROUP_PAGE_SIZE,
                }),
                // A new order would otherwise keep a stale "first N" across sections
                setSort: () => ({}),
                setProductFilter: () => ({}),
                setScope: () => ({}),
            },
        ],
        openGroups: [
            { decision: true, monitoring: true, resolved: false } as Record<string, boolean>,
            {
                toggleGroupOpen: (state, { group }) => ({ ...state, [group]: !state[group] }),
            },
        ],
        productFilter: [null as string | null, { setProductFilter: (_, { product }) => product }],
        scope: ['for-you' as InboxDemoScope, { setScope: (_, { scope }) => scope }],
        expandedRowId: [
            null as string | null,
            { toggleRowExpanded: (current, { id }) => (current === id ? null : id) },
        ],
        prModalTarget: [
            null as InboxPrModalTarget | null,
            {
                openPrModal: (_, { target }) => target,
                closePrModal: () => null,
            },
        ],
        assignedProducts: [
            DEFAULT_ASSIGNED_PRODUCTS,
            {
                toggleAssignedProduct: (state, { area }) =>
                    state.includes(area) ? state.filter((item) => item !== area) : [...state, area],
            },
        ],
        toggles: [
            DEFAULT_DEMO_TOGGLES,
            {
                toggleSetting: (state, { key }) => ({ ...state, [key]: !state[key] }),
            },
        ],
    }),
    selectors({
        filteredReports: [
            (s) => [s.filter, s.productFilter, s.scope, s.assignedProducts],
            (
                filter: InboxDemoFilter,
                productFilter: string | null,
                scope: InboxDemoScope,
                assignedProducts: string[]
            ): DemoReport[] =>
                DEMO_REPORTS.filter(
                    (report) =>
                        matchesFilter(report, filter) &&
                        (productFilter === null || report.area === productFilter) &&
                        (scope === 'project' || assignedProducts.includes(report.area))
                ).sort((a, b) => b.impactWeight - a.impactWeight),
        ],
        groupedReports: [
            (s) => [s.productFilter, s.scope, s.assignedProducts, s.sort],
            (
                productFilter: string | null,
                scope: InboxDemoScope,
                assignedProducts: string[],
                sort: InboxDemoSort
            ): InboxReportGroup[] => {
                const visible = DEMO_REPORTS.filter(
                    (report) =>
                        (productFilter === null || report.area === productFilter) &&
                        (scope === 'project' || assignedProducts.includes(report.area))
                ).sort(compareReports(sort))
                const byGroup = (key: InboxDemoGroup): DemoReport[] =>
                    visible.filter((report) => groupFor(report) === key)
                return [
                    { key: 'decision', label: 'Needs a decision', reports: byGroup('decision') },
                    { key: 'monitoring', label: 'Monitoring', reports: byGroup('monitoring') },
                    { key: 'resolved', label: 'Resolved', reports: byGroup('resolved') },
                ]
            },
        ],
    }),
    listeners(({ values }) => ({
        confirmPrModal: () => {
            // The report page reads the `#fix` hash and starts its fix flow on arrival.
            if (values.prModalTarget) {
                router.actions.push(`${urls.v2Report(values.prModalTarget.reportId)}#fix`)
            }
        },
    })),
])
