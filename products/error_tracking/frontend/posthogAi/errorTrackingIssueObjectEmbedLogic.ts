/**
 * Loads one issue and its volume for a read-only embed. It does not use `errorTrackingIssueSceneLogic`, because that
 * logic writes the selected event and the filters to the page URL and so changes the URL of the page that shows the embed.
 */
export const errorTrackingIssueObjectEmbedLogic = kea<errorTrackingIssueObjectEmbedLogicType>([
    props({} as ErrorTrackingIssueObjectEmbedLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'error_tracking', 'posthogAi', 'errorTrackingIssueObjectEmbedLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentProjectId']] })),
    actions({ setIssueMissing: true }),
    loaders(({ props, values, actions }) => ({
        issue: [
            null as ErrorTrackingIssueReadApi | null,
            {
                loadIssue: async (): Promise<ErrorTrackingIssueReadApi | null> => {
                    try {
                        return await errorTrackingIssuesRetrieve(String(values.currentProjectId), props.id)
                    } catch (error: any) {
                        if (error.status === 404 || error.status === 400) {
                            actions.setIssueMissing()
                            return null
                        }
                        throw error
                    }
                },
            },
        ],
        summary: [
            null as ErrorTrackingIssueEmbedSummary | null,
            {
                loadSummary: async (): Promise<ErrorTrackingIssueEmbedSummary> => {
                    const response = await api.query(
                        errorTrackingIssueQuery({
                            issueId: props.id,
                            dateRange: DEFAULT_DATE_RANGE,
                            filterTestAccounts: false,
                            volumeResolution: ERROR_TRACKING_DETAILS_RESOLUTION,
                            withAggregations: true,
                        })
                    )
                    const result = response.results[0]
                    return { aggregations: result?.aggregations ?? null, lastSeen: result?.last_seen ?? null }
                },
            },
        ],
    })),
    reducers({
        issueMissing: [false, { setIssueMissing: () => true }],
    }),
    afterMount(({ props, actions }) => {
        // A non-UUID id is never a real issue, so show the missing state without a request that would fail.
        if (!isUUIDLike(props.id)) {
            actions.setIssueMissing()
            return
        }
        actions.loadIssue()
        actions.loadSummary()
    }),
])
