export type errorTrackingBannersLogicType = MakeLogicType<
    errorTrackingBannersLogicValues,
    errorTrackingBannersLogicActions,
    Record<string, any>,
    errorTrackingBannersLogicMeta
>

export const errorTrackingBannersLogic = kea<errorTrackingBannersLogicType>([
    path(['products', 'error_tracking', 'scenes', 'ErrorTrackingScene', 'banners', 'errorTrackingBannersLogic']),

    connect(() => ({
        values: [
            recommendationsLogic,
            ['recommendations'],
            lemonBannerLogic({ dismissKey: SOURCE_MAPS_BANNER_DISMISS_KEY }),
            ['isDismissed as sourceMapsBannerDismissed'],
            lemonBannerLogic({ dismissKey: ALERTS_BANNER_DISMISS_KEY }),
            ['isDismissed as alertsBannerDismissed'],
            lemonBannerLogic({ dismissKey: RATE_LIMITS_BANNER_DISMISS_KEY }),
            ['isDismissed as rateLimitsBannerDismissed'],
        ],
        actions: [
            recommendationsLogic,
            ['refreshRecommendation'],
            lemonBannerLogic({ dismissKey: SOURCE_MAPS_BANNER_DISMISS_KEY }),
            ['dismiss as dismissSourceMapsBanner'],
            lemonBannerLogic({ dismissKey: ALERTS_BANNER_DISMISS_KEY }),
            ['dismiss as dismissAlertsBanner'],
            lemonBannerLogic({ dismissKey: RATE_LIMITS_BANNER_DISMISS_KEY }),
            ['dismiss as dismissRateLimitsBanner'],
        ],
    })),

    actions({
        dismissBanner: (banner: ErrorTrackingBannerKey) => ({ banner }),
        showPreviousBanner: true,
        showNextBanner: true,
        setSelectedBanner: (banner: ErrorTrackingBannerKey | null) => ({ banner }),
        openAlertSetup: (triggerKey: HogFunctionSubTemplateIdType | null) => ({ triggerKey }),
        closeAlertSetup: true,
    }),

    reducers({
        isAlertSetupOpen: [
            false,
            {
                openAlertSetup: () => true,
                closeAlertSetup: () => false,
            },
        ],
        alertSetupTriggerKey: [
            null as HogFunctionSubTemplateIdType | null,
            {
                openAlertSetup: (_, { triggerKey }) => triggerKey,
            },
        ],
        selectedBanner: [
            null as ErrorTrackingBannerKey | null,
            {
                setSelectedBanner: (_, { banner }) => banner,
            },
        ],
    }),

    selectors({
        sourceMapsRecommendation: [
            (s) => [s.recommendations],
            (recommendations: ErrorTrackingRecommendationApi[]): SourceMapsRecommendation | null =>
                recommendations.find(isSourceMapsRecommendation) ?? null,
        ],
        alertsRecommendation: [
            (s) => [s.recommendations],
            (recommendations: ErrorTrackingRecommendationApi[]): AlertsRecommendation | null =>
                recommendations.find(isAlertsRecommendation) ?? null,
        ],
        rateLimitsRecommendation: [
            (s) => [s.recommendations],
            (recommendations: ErrorTrackingRecommendationApi[]): RateLimitsRecommendation | null =>
                recommendations.find(isRateLimitsRecommendation) ?? null,
        ],
        activeBanners: [
            (s) => [
                s.sourceMapsRecommendation,
                s.alertsRecommendation,
                s.rateLimitsRecommendation,
                s.sourceMapsBannerDismissed,
                s.alertsBannerDismissed,
                s.rateLimitsBannerDismissed,
            ],
            (
                sourceMapsRecommendation: SourceMapsRecommendation | null,
                alertsRecommendation: AlertsRecommendation | null,
                rateLimitsRecommendation: RateLimitsRecommendation | null,
                sourceMapsBannerDismissed: boolean,
                alertsBannerDismissed: boolean,
                rateLimitsBannerDismissed: boolean
            ): ErrorTrackingBannerKey[] =>
                // Unreadable stack traces block triage, so that banner goes first.
                activeBanners([
                    {
                        key: 'source_maps',
                        state: candidateState(sourceMapsRecommendation, (r) => !r.completed),
                        dismissed: sourceMapsBannerDismissed,
                    },
                    {
                        key: 'alerts',
                        state: candidateState(
                            alertsRecommendation,
                            (r) => !r.completed && (r.meta.alerts ?? []).length > 0
                        ),
                        dismissed: alertsBannerDismissed,
                    },
                    {
                        key: 'rate_limits',
                        // Only the project-wide limit gets a banner. The per-issue limit is optional tuning.
                        state: candidateState(rateLimitsRecommendation, (r) =>
                            (r.meta.rate_limits ?? []).some((limit) => limit.key === 'project' && !limit.enabled)
                        ),
                        dismissed: rateLimitsBannerDismissed,
                    },
                ]),
        ],
        currentBanner: [
            (s) => [s.activeBanners, s.selectedBanner],
            (
                active: ErrorTrackingBannerKey[],
                selected: ErrorTrackingBannerKey | null
            ): ErrorTrackingBannerKey | null => currentBanner(active, selected),
        ],
        currentBannerIndex: [
            (s) => [s.activeBanners, s.currentBanner],
            (active: ErrorTrackingBannerKey[], current: ErrorTrackingBannerKey | null): number =>
                current ? active.indexOf(current) : -1,
        ],
    }),

    listeners(({ actions, values }) => {
        const navigateTo = (direction: 'previous' | 'next'): void => {
            const target = stepBanner(values.activeBanners, values.currentBanner, direction)
            if (!target || target === values.currentBanner) {
                return
            }
            actions.setSelectedBanner(target)
            posthog.capture('error_tracking_banner_navigated', {
                banner: target,
                direction,
                position: values.activeBanners.indexOf(target) + 1,
                total: values.activeBanners.length,
            })
        }

        return {
            dismissBanner: ({ banner }) => {
                // Keep the user at the same spot in the stack rather than jumping back to the top.
                if (banner === values.currentBanner) {
                    actions.setSelectedBanner(bannerAfterDismiss(values.activeBanners, banner))
                }
                if (banner === 'source_maps') {
                    actions.dismissSourceMapsBanner()
                } else if (banner === 'alerts') {
                    actions.dismissAlertsBanner()
                } else {
                    actions.dismissRateLimitsBanner()
                }
                // pinned: analytics event names. Renaming them breaks dashboards.
                posthog.capture(`error_tracking_${banner}_banner_dismissed`)
            },
            showPreviousBanner: () => navigateTo('previous'),
            showNextBanner: () => navigateTo('next'),
            openAlertSetup: ({ triggerKey }) => {
                posthog.capture('error_tracking_alert_creation_started', {
                    ui_source: 'alerts_banner',
                    trigger_key: triggerKey,
                })
            },
            closeAlertSetup: () => {
                // Recompute right away so the banner hides, or narrows to the alerts still missing.
                if (values.alertsRecommendation) {
                    actions.refreshRecommendation(values.alertsRecommendation.id)
                }
            },
        }
    }),
])
