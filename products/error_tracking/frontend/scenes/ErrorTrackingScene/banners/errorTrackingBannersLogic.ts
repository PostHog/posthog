import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { lemonBannerLogic } from 'lib/lemon-ui/LemonBanner/lemonBannerLogic'

import { HogFunctionSubTemplateIdType } from '~/types'

import type { ErrorTrackingRecommendationApi } from '../../../generated/api.schemas'
import {
    ErrorTrackingBannerKey,
    activeBanners,
    bannerAfterDismiss,
    candidateState,
    currentBanner,
    stepBanner,
} from './bannerQueue'
import { recommendationsLogic } from './recommendationsLogic'
import type { AlertsRecommendation, RateLimitsRecommendation, SourceMapsRecommendation } from './types'

// pinned: localStorage keys. Renaming one resets every user's dismissal.
export const SOURCE_MAPS_BANNER_DISMISS_KEY = 'error-tracking-source-maps-banner'
export const ALERTS_BANNER_DISMISS_KEY = 'error-tracking-alerts-banner'
export const RATE_LIMITS_BANNER_DISMISS_KEY = 'error-tracking-rate-limits-banner'

const isSourceMapsRecommendation = (r: ErrorTrackingRecommendationApi): r is SourceMapsRecommendation =>
    r.type === 'source_maps'

const isAlertsRecommendation = (r: ErrorTrackingRecommendationApi): r is AlertsRecommendation => r.type === 'alerts'

const isRateLimitsRecommendation = (r: ErrorTrackingRecommendationApi): r is RateLimitsRecommendation =>
    r.type === 'rate_limits'

