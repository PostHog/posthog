    alertsBannerDismissed: boolean // lemonBannerLogic
    rateLimitsBannerDismissed: boolean // lemonBannerLogic
    sourceMapsBannerDismissed: boolean // lemonBannerLogic
    recommendations: ErrorTrackingRecommendationApi[] // recommendationsLogic
    activeBanners: ErrorTrackingBannerKey[]
    alertSetupTriggerKey: HogFunctionSubTemplateIdType | null
    alertsRecommendation: AlertsRecommendation | null
    currentBanner: ErrorTrackingBannerKey | null
    currentBannerIndex: number
    isAlertSetupOpen: boolean
    rateLimitsRecommendation: RateLimitsRecommendation | null
    selectedBanner: ErrorTrackingBannerKey | null
    sourceMapsRecommendation: SourceMapsRecommendation | null
