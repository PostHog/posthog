export const errorTrackingInsightsLogic = kea<errorTrackingInsightsLogicType>([
    path([
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingScene',
        'tabs',
        'insights',
        'errorTrackingInsightsLogic',
    ]),

    connect(() => ({
        values: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_SCENE_LOGIC_KEY }),
            ['dateRange', 'filterTestAccounts', 'filterGroup', 'mergedFilterGroup'],
            teamLogic,
            ['timezone'],
        ],
        actions: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_SCENE_LOGIC_KEY }),
            ['setDateRange', 'setFilterGroup', 'setFilterTestAccounts', 'addPropertyFilter'],
        ],
    })),

    actions({
        loadInsights: () => {},
        filterByBand: (filters: BandFilter[]) => ({ filters }),
    }),

    reducers({
        loadFailed: [
            false,
            {
                loadInsights: () => false,
                loadComparisonTotalsFailure: () => true,
                loadSummaryBucketsFailure: () => true,
                loadReleaseRowsFailure: () => true,
                loadAppRowsFailure: () => true,
            },
        ],
    }),

    loaders(({ values }) => ({
        comparisonTotals: [
            EMPTY_COMPARISON_TOTALS,
            {
                loadComparisonTotals: async (_: void, breakpoint): Promise<ComparisonTotals> => {
                    await breakpoint(10)
                    const window = buildComparisonWindow(
                        values.effectiveDateRange.date_from ?? null,
                        values.effectiveDateRange.date_to ?? null,
                        values.timezone,
                        values.interval
                    )
                    const response = (await api.query({
                        kind: NodeKind.HogQLQuery,
                        query: buildComparisonTotalsQuery(window.currentStart, values.timezone),
                        filters: {
                            dateRange: { date_from: window.dateFrom, date_to: window.dateTo },
                            filterTestAccounts: values.filterTestAccounts,
                            properties: values.effectiveProperties,
                        },
                        tags: { productKey: ProductKey.ERROR_TRACKING },
                    })) as HogQLQueryResponse
                    breakpoint()
                    return parseComparisonTotals((response?.results as unknown[][]) ?? [])
                },
            },
        ],
        summaryBuckets: [
            [] as SummaryBucket[],
            {
                loadSummaryBuckets: async (_: void, breakpoint): Promise<SummaryBucket[]> => {
                    await breakpoint(10)
                    const response = (await api.query({
                        kind: NodeKind.HogQLQuery,
                        query: buildSummarySeriesQuery(values.interval),
                        filters: {
                            dateRange: values.effectiveDateRange,
                            filterTestAccounts: values.filterTestAccounts,
                            properties: values.effectiveProperties,
                        },
                        tags: { productKey: ProductKey.ERROR_TRACKING },
                    })) as HogQLQueryResponse
                    breakpoint()
                    return parseSummaryBuckets((response?.results as unknown[][]) ?? [])
                },
            },
        ],
        appRows: [
            [] as ReleaseRow[],
            {
                loadAppRows: async (_: void, breakpoint): Promise<ReleaseRow[]> => {
                    await breakpoint(10)
                    const response = (await api.query({
                        kind: NodeKind.HogQLQuery,
                        query: buildAppBreakdownQuery(values.interval, MAX_RELEASE_ROWS),
                        filters: {
                            dateRange: values.effectiveDateRange,
                            filterTestAccounts: values.filterTestAccounts,
                            properties: values.effectiveProperties,
                        },
                        tags: { productKey: ProductKey.ERROR_TRACKING },
                    })) as HogQLQueryResponse
                    breakpoint()
                    return parseReleaseRows((response?.results as unknown[][]) ?? [], values.bucketKeys)
                },
            },
        ],
        releaseRows: [
            [] as ReleaseRow[],
            {
                loadReleaseRows: async (_: void, breakpoint): Promise<ReleaseRow[]> => {
                    await breakpoint(10)
                    const response = (await api.query({
                        kind: NodeKind.HogQLQuery,
                        query: buildReleaseBreakdownQuery(values.interval, MAX_RELEASE_ROWS),
                        filters: {
                            dateRange: values.effectiveDateRange,
                            filterTestAccounts: values.filterTestAccounts,
                            properties: values.effectiveProperties,
                        },
                        tags: { productKey: ProductKey.ERROR_TRACKING },
                    })) as HogQLQueryResponse
                    breakpoint()
                    return parseReleaseRows((response?.results as unknown[][]) ?? [], values.bucketKeys)
                },
            },
        ],
    })),

    selectors({
        insightsFilterGroup: [
            (s) => [s.mergedFilterGroup],
            (mergedFilterGroup: UniversalFiltersGroup): UniversalFiltersGroup => {
                const inner = mergedFilterGroup.values[0] as UniversalFiltersGroup
                return {
                    type: FilterLogicalOperator.And,
                    values: [stripIssueFiltersFromGroup(inner)],
                } as UniversalFiltersGroup
            },
        ],
        // Flat property list shared by the HogQL summary query and the embedded TrendsQuery charts.
        // Both paths must use the same shape — passing a wrapped group to one path and a flat list
        // to the other can cause the summary stats and charts to disagree on which events match.
        effectiveProperties: [
            (s) => [s.insightsFilterGroup],
            (insightsFilterGroup: UniversalFiltersGroup): AnyPropertyFilter[] => {
                const inner = insightsFilterGroup.values[0] as UniversalFiltersGroup | undefined
                return (inner?.values ?? []) as AnyPropertyFilter[]
            },
        ],
        // Single source of truth for the date range used by both the summary stats query and the charts.
        effectiveDateRange: [
            (s) => [s.dateRange],
            (dateRange: DateRange): DateRange => ({
                date_from: dateRange.date_from ?? '-7d',
                date_to: dateRange.date_to ?? null,
            }),
        ],
        // The charts and the metric tiles have to bucket the same way, or a tile's sparkline reads as
        // a different shape than the chart directly below it.
        interval: [
            (s) => [s.effectiveDateRange],
            (dateRange: DateRange): IntervalType => getInterval(dateRange.date_from, dateRange.date_to),
        ],
        bucketKeys: [
            (s) => [s.effectiveDateRange, s.timezone, s.interval],
            (dateRange: DateRange, timezone: string, interval: IntervalType): string[] =>
                buildBucketKeys(dateRange.date_from ?? null, dateRange.date_to ?? null, timezone, interval),
        ],
        incompleteTail: [
            (s) => [s.bucketKeys, s.timezone, s.interval],
            (bucketKeys: string[], timezone: string, interval: IntervalType): boolean =>
                lastBucketIsInProgress(bucketKeys, timezone, interval),
        ],
        insightQueryFilters: [
            (s) => [s.effectiveProperties, s.filterTestAccounts],
            (properties: AnyPropertyFilter[], filterTestAccounts: boolean): InsightQueryFilters => ({
                properties,
                filterTestAccounts,
            }),
        ],
        metrics: [
            (s) => [s.comparisonTotals, s.summaryBuckets, s.bucketKeys, s.interval],
            (
                totals: ComparisonTotals,
                buckets: SummaryBucket[],
                bucketKeys: string[],
                interval: IntervalType
            ): InsightsMetrics => buildMetrics(totals, buckets, bucketKeys, interval),
        ],
        // The tiles read both queries, so they stay in their loading state until both have answered
        // rather than showing a headline number above a sparkline that is still empty.
        metricsLoading: [
            (s) => [s.comparisonTotalsLoading, s.summaryBucketsLoading],
            (totalsLoading: boolean, bucketsLoading: boolean): boolean => totalsLoading || bucketsLoading,
        ],
        exceptionVolumeQuery: [
            (s) => [s.effectiveDateRange, s.insightQueryFilters],
            (dateRange: DateRange, filters: InsightQueryFilters): InsightVizNode<TrendsQuery> =>
                buildExceptionVolumeQuery(dateRange, filters),
        ],
        issuesCreatedQuery: [
            (s) => [s.effectiveDateRange, s.insightQueryFilters],
            (dateRange: DateRange, filters: InsightQueryFilters): InsightVizNode<TrendsQuery> =>
                buildIssuesCreatedQuery(dateRange, filters),
        ],
        affectedUsersQuery: [
            (s) => [s.effectiveDateRange, s.insightQueryFilters],
            (dateRange: DateRange, filters: InsightQueryFilters): InsightVizNode<TrendsQuery> =>
                buildAffectedUsersQuery(dateRange, filters),
        ],
        crashFreeSessionsQuery: [
            (s) => [s.effectiveDateRange, s.insightQueryFilters],
            (dateRange: DateRange, filters: InsightQueryFilters): InsightVizNode<TrendsQuery> =>
                buildCrashFreeSessionsQuery(dateRange, filters),
        ],
    }),

    listeners(({ actions, values }) => ({
        loadInsights: () => {
            actions.loadComparisonTotals()
            actions.loadSummaryBuckets()
            actions.loadReleaseRows()
            actions.loadAppRows()
        },
        setDateRange: () => {
            actions.loadInsights()
        },
        setFilterTestAccounts: () => {
            actions.loadInsights()
        },
        // A band with no value for a property filters on "is not set", so a click never leaves a stale
        // chip from the band clicked before it.
        filterByBand: ({ filters }) => {
            for (const { key, value } of filters) {
                actions.addPropertyFilter(
                    key,
                    value,
                    value === null ? PropertyOperator.IsNotSet : PropertyOperator.Exact,
                    false,
                    true
                )
            }
            // A band is one value spread over several properties, so its chips only mean what the
            // panel says while they combine with AND. Added to a group the user set to "Any" they
            // would instead match anything carrying any one of them.
            const group = values.filterGroup
            const first = group.values[0]
            const conjunctive =
                isUniversalGroupFilterLike(first) && first.type !== FilterLogicalOperator.And
                    ? {
                          ...group,
                          values: [{ ...first, type: FilterLogicalOperator.And }, ...group.values.slice(1)],
                      }
                    : group
            // Each add resets the preview-added count to one chip, so all but the last of these would
            // open its value editor on the next render. Re-count every chip this click added, which
            // lands the band as chips alone.
            actions.setFilterGroup(conjunctive, filters.length)
        },
    })),

    subscriptions(({ actions }) => ({
        insightsFilterGroup: () => {
            actions.loadInsights()
        },
    })),

    afterMount(({ actions }) => {
        posthog.capture('error_tracking_insights_viewed')
        actions.loadInsights()
    }),
])
