function lensState(lens: ErrorTrackingRecommendation, computingIds: Set<string>): ImpactLensState {
    if (computingIds.has(lens.id)) {
        return 'computing'
    }
    if (lens.computed_at === null) {
        return 'pending'
    }
    return lens.meta.evaluable === false ? 'unavailable' : 'ready'
}

// Each impact lens is computed and served as a recommendation, so this logic reuses the
// recommendations logic for loading, refreshing and polling instead of fetching on its own.
export const impactTabLogic = kea<impactTabLogicType>([
    path(['products', 'error_tracking', 'scenes', 'ErrorTrackingScene', 'tabs', 'impact', 'impactTabLogic']),

    connect(() => ({
        values: [
            recommendationsTabLogic,
            ['recommendations', 'recommendationsLoading', 'recommendationsLoadFailed', 'computingIds'],
            issueActionsLogic,
            ['mergeInFlight'],
        ],
        actions: [
            recommendationsTabLogic,
            ['refreshRecommendation', 'loadRecommendations'],
            issueActionsLogic,
            ['mergeIssues', 'mutationSuccess'],
        ],
    })),

    actions({
        // selectView is a person picking a view; setView follows the URL, so only selectView is tracked.
        selectView: (view: ImpactView) => ({ view }),
        setView: (view: ImpactView) => ({ view }),
        refreshLens: (id: string) => ({ id }),
        refreshUncalculatedLenses: true,
        reportIssueClicked: (lensType: ImpactLensType, issueId: string) => ({ lensType, issueId }),
        mergeRelatedIssues: (targetId: string, sourceId: string) => ({ targetId, sourceId }),
    }),

    reducers({
        selectedView: [
            'all' as ImpactView,
            {
                selectView: (_, { view }) => view,
                setView: (_, { view }) => view,
            },
        ],
    }),

    selectors({
        lenses: [
            (s) => [s.recommendations],
            (recommendations: ErrorTrackingRecommendation[]): ErrorTrackingRecommendation[] =>
                IMPACT_LENS_TYPES.flatMap((type) => recommendations.filter((r) => r.type === type)),
        ],
        lensesByType: [
            (s) => [s.lenses],
            (lenses: ErrorTrackingRecommendation[]): Partial<Record<ImpactLensType, ErrorTrackingRecommendation>> =>
                Object.fromEntries(lenses.map((lens) => [lens.type, lens])),
        ],
        lensTypes: [
            (s) => [s.lenses],
            (lenses: ErrorTrackingRecommendation[]): ImpactLensType[] =>
                lenses.map((lens) => lens.type).filter(isImpactLensType),
        ],
        findings: [
            (s) => [s.lenses],
            (lenses: ErrorTrackingRecommendation[]): Partial<Record<ImpactFindingLens, ImpactFinding[]>> =>
                findingsByLens(lenses),
        ],
        lensStates: [
            (s) => [s.lenses, s.computingIds],
            (
                lenses: ErrorTrackingRecommendation[],
                computingIds: Set<string>
            ): Partial<Record<ImpactLensType, ImpactLensState>> =>
                Object.fromEntries(lenses.map((lens) => [lens.type, lensState(lens, computingIds)])),
        ],
        lensCounts: [
            (s) => [s.findings],
            (findings: Partial<Record<ImpactFindingLens, ImpactFinding[]>>): Partial<Record<ImpactLensType, number>> =>
                Object.fromEntries(Object.entries(findings).map(([lens, list]) => [lens, list.length])),
        ],
        totalCount: [
            (s) => [s.lensCounts],
            (lensCounts: Partial<Record<ImpactLensType, number>>): number =>
                IMPACT_LENS_TYPES.filter((type) => !isNoiseLensType(type)).reduce(
                    (total, type) => total + (lensCounts[type] ?? 0),
                    0
                ),
        ],
        activeView: [
            (s) => [s.selectedView, s.lensTypes],
            (selectedView: ImpactView, lensTypes: ImpactLensType[]): ImpactView =>
                selectedView === 'all' || lensTypes.includes(selectedView) ? selectedView : 'all',
        ],
        activeFindings: [
            (s) => [s.activeView, s.lensTypes, s.findings],
            (
                activeView: ImpactView,
                lensTypes: ImpactLensType[],
                findings: Partial<Record<ImpactFindingLens, ImpactFinding[]>>
            ): ImpactFinding[] =>
                activeView === 'all'
                    ? lensTypes.filter((type) => !isNoiseLensType(type)).flatMap((type) => findings[type] ?? [])
                    : (findings[activeView] ?? []),
        ],
        activeViewProgress: [
            (s) => [s.activeView, s.lenses, s.computingIds],
            (
                activeView: ImpactView,
                lenses: ErrorTrackingRecommendation[],
                computingIds: Set<string>
            ): ImpactLensProgress[] =>
                lenses
                    .filter((lens) =>
                        activeView === 'all'
                            ? isImpactLensType(lens.type) && !isNoiseLensType(lens.type)
                            : lens.type === activeView
                    )
                    .map((lens) => ({
                        computing: computingIds.has(lens.id),
                        calculated: lens.computed_at !== null,
                        evaluable: lens.meta.evaluable !== false,
                    })),
        ],
        uncalculatedCount: [
            (s) => [s.activeViewProgress],
            (progress: ImpactLensProgress[]): number => progress.filter((lens) => !lens.calculated).length,
        ],
        unavailableCount: [
            (s) => [s.activeViewProgress],
            (progress: ImpactLensProgress[]): number =>
                progress.filter((lens) => lens.calculated && !lens.evaluable).length,
        ],
        viewStatus: [
            (s) => [s.activeViewProgress, s.activeFindings],
            (progress: ImpactLensProgress[], activeFindings: ImpactFinding[]): ImpactViewStatus =>
                impactViewStatus(progress, activeFindings.length),
        ],
        tabStatus: [
            (s) => [s.lenses, s.recommendationsLoading, s.recommendationsLoadFailed],
            (lenses: ErrorTrackingRecommendation[], loading: boolean, loadFailed: boolean): ImpactTabStatus =>
                impactTabStatus({ lensCount: lenses.length, loading, loadFailed }),
        ],
    }),

    listeners(({ actions, values }) => ({
        selectView: ({ view }) => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('error_tracking_impact_lens_selected', { lens_type: view })
        },
        refreshUncalculatedLenses: () => {
            for (const lens of values.lenses) {
                if (lens.computed_at === null && !values.computingIds.has(lens.id)) {
                    actions.refreshLens(lens.id)
                }
            }
        },
        refreshLens: ({ id }) => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('error_tracking_impact_lens_refreshed', {
                lens_type: values.lenses.find((lens) => lens.id === id)?.type,
            })
            actions.refreshRecommendation(id)
        },
        reportIssueClicked: ({ lensType, issueId }) => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('error_tracking_impact_issue_clicked', { issue_id: issueId, lens_type: lensType })
        },
        mergeRelatedIssues: ({ targetId, sourceId }) => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('error_tracking_impact_issues_merged', { target_id: targetId, source_id: sourceId })
            actions.mergeIssues([targetId, sourceId])
        },
        mutationSuccess: ({ mutationName }) => {
            // A merge removes an issue, so recompute the pairs rather than show one that no longer exists.
            const related = values.lensesByType.related_issues
            if (mutationName === 'mergeIssues' && related) {
                actions.refreshRecommendation(related.id)
            }
        },
    })),

    // The open view lives in the URL, so a link can point at one lens, and back and forward move between views.
    urlToAction(({ actions, values }) => ({
        '**/error_tracking': (_, params) => {
            const lens = params.lens
            const view: ImpactView =
                typeof lens === 'string' && (IMPACT_LENS_TYPES as readonly string[]).includes(lens)
                    ? (lens as ImpactLensType)
                    : 'all'
            if (view !== values.selectedView) {
                actions.setView(view)
            }
        },
    })),

    actionToUrl(({ values }) => ({
        selectView: () =>
            syncSearchParams(router, (params: Params) => {
                updateSearchParams(params, 'lens', values.selectedView, 'all')
                return params
            }),
    })),

    afterMount(() => {
        // pinned: analytics event name, renaming breaks dashboards
        posthog.capture('error_tracking_impact_viewed')
    }),
])
