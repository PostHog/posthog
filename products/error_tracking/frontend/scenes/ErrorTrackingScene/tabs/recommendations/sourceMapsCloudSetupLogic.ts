/**
 * Drives the cloud setup flow of the source maps fix modal: picks a GitHub account and
 * repository, triggers a cloud detection scan and polls it, lists the detected projects,
 * and launches the detection-based cloud run for a picked project, polling its task run until the
 * pull request is ready. Mounted only while the modal is open, so unmount tears the
 * polling and timers down.
 */
export const sourceMapsCloudSetupLogic = kea<sourceMapsCloudSetupLogicType>([
    path([
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingScene',
        'tabs',
        'recommendations',
        'sourceMapsCloudSetupLogic',
    ]),
    connect(() => ({
        values: [integrationsLogic, ['integrations'], teamLogic, ['currentProjectId']],
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        setStep: (step: CloudSetupStep) => ({ step }),
        setSelectedIntegrationId: (integrationId: number | null) => ({ integrationId }),
        setSelectedRepository: (repository: string | null) => ({ repository }),
        continueFromRepository: true,
        startDetection: true,
        startDetectionSuccess: true,
        startDetectionFailure: true,
        advanceScanStep: true,
        resetScanSteps: true,
        startDetectionBasedRun: (project: DetectedProject) => ({ project }),
        startDetectionBasedRunSuccess: (handle: DetectionBasedRunHandle) => ({ handle }),
        startDetectionBasedRunFailure: true,
        dismissDetectionBasedRun: true,
    }),
    loaders(({ values }) => ({
        detections: [
            [] as RepositoryDetection[],
            {
                loadDetections: async () =>
                    await api.get<RepositoryDetection[]>(
                        `api/wizard/repository_detections?project_id=${values.currentProjectId}&kind=${SOURCE_MAPS_DETECTION_KIND}`
                    ),
            },
        ],
        detectionBasedRunDetail: [
            null as TaskRunDetailDTOApi | null,
            {
                loadDetectionBasedRun: async () => {
                    const { detectionBasedRun, currentProjectId } = values
                    if (!detectionBasedRun) {
                        return null
                    }
                    return await tasksRunsRetrieve(
                        String(currentProjectId),
                        detectionBasedRun.taskId,
                        detectionBasedRun.runId
                    )
                },
            },
        ],
    })),
    reducers({
        step: [
            'intro' as CloudSetupStep,
            {
                setStep: (_, { step }) => step,
                // Starting a scan advances the flow on its own.
                startDetectionSuccess: () => 'project',
            },
        ],
        selectedIntegrationId: [
            null as number | null,
            {
                setSelectedIntegrationId: (_, { integrationId }) => integrationId,
            },
        ],
        selectedRepository: [
            null as string | null,
            {
                setSelectedRepository: (_, { repository }) => repository,
                // Repositories belong to an account, so switching accounts invalidates the pick.
                setSelectedIntegrationId: () => null,
            },
        ],
        isStartingDetection: [
            false,
            {
                startDetection: () => true,
                startDetectionSuccess: () => false,
                startDetectionFailure: () => false,
            },
        ],
        scanStepIndex: [
            0,
            {
                resetScanSteps: () => 0,
                advanceScanStep: (state) => Math.min(state + 1, SCAN_STEPS.length - 1),
            },
        ],
        detectionBasedRun: [
            null as DetectionBasedRunHandle | null,
            {
                startDetectionBasedRunSuccess: (_, { handle }) => handle,
                dismissDetectionBasedRun: () => null,
                // The handle belongs to the picked repository; switching repositories drops it
                // (the run itself keeps going server-side).
                setSelectedRepository: () => null,
            },
        ],
        // Path of the project whose trigger request is in flight; drives the per-option
        // loading state and blocks a second submission while one is pending.
        startingDetectionBasedRunPath: [
            null as string | null,
            {
                startDetectionBasedRun: (_, { project }) => project.path,
                startDetectionBasedRunSuccess: () => null,
                startDetectionBasedRunFailure: () => null,
            },
        ],
        // Extends the loader's reducer: dropping the handle must also drop the stale detail,
        // or the next run would briefly render the previous run's terminal state.
        detectionBasedRunDetail: [
            null as TaskRunDetailDTOApi | null,
            {
                startDetectionBasedRunSuccess: () => null,
                dismissDetectionBasedRun: () => null,
                setSelectedRepository: () => null,
            },
        ],
    }),
    selectors({
        githubIntegrations: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): IntegrationType[] =>
                integrations?.filter((integration) => integration.kind === 'github') ?? [],
        ],
        // Defaults to the first connected account so the row renders complete (and the owner
        // resolves) before the user makes an explicit choice.
        selectedIntegration: [
            (s) => [s.githubIntegrations, s.selectedIntegrationId],
            (githubIntegrations: IntegrationType[], selectedIntegrationId: number | null): IntegrationType | null =>
                selectedIntegrationId != null
                    ? (githubIntegrations.find((integration) => integration.id === selectedIntegrationId) ?? null)
                    : (githubIntegrations[0] ?? null),
        ],
        // The picker holds the bare repo name; the endpoint and the detection rows use
        // "owner/repo", where the owner is the selected GitHub account.
        selectedRepositoryFull: [
            (s) => [s.selectedRepository, s.selectedIntegration],
            (selectedRepository: string | null, selectedIntegration: IntegrationType | null): string | null => {
                if (!selectedRepository) {
                    return null
                }
                const owner = selectedIntegration?.config?.account?.name
                return selectedRepository.includes('/') || !owner
                    ? selectedRepository
                    : `${owner}/${selectedRepository}`
            },
        ],
        selectedDetection: [
            (s) => [s.detections, s.selectedRepositoryFull],
            (detections: RepositoryDetection[], selectedRepositoryFull: string | null): RepositoryDetection | null =>
                detections.find((detection) => detection.repository === selectedRepositoryFull) ?? null,
        ],
        isScanRunning: [
            (s) => [s.selectedDetection],
            (selectedDetection: RepositoryDetection | null): boolean => isLiveDetection(selectedDetection),
        ],
        // Live until the polled run reaches a terminal status; a handle with no detail yet
        // (first poll still in flight) counts as live so the progress view shows immediately.
        isDetectionBasedRunLive: [
            (s) => [s.detectionBasedRun, s.detectionBasedRunDetail],
            (
                detectionBasedRun: DetectionBasedRunHandle | null,
                detectionBasedRunDetail: TaskRunDetailDTOApi | null
            ): boolean =>
                !!detectionBasedRun &&
                (!detectionBasedRunDetail?.status || LIVE_TASK_RUN_STATUSES.includes(detectionBasedRunDetail.status)),
        ],
        detectionBasedRunPrUrl: [
            (s) => [s.detectionBasedRunDetail],
            (detectionBasedRunDetail: TaskRunDetailDTOApi | null): string | null => {
                const url = detectionBasedRunDetail?.output?.['pr_url']
                return typeof url === 'string' && url ? url : null
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        // The step copy is keyed to the selected repo's live run: a new run restarts it from
        // the first step, a finished (or deselected) run stops it. Re-armed with the same run
        // id it must be left alone — replacing the interval would reset its 5s cadence on
        // every poll tick and the copy would never advance.
        const syncScanStepTicker = (): void => {
            const detection = values.selectedDetection
            const liveRunId = isLiveDetection(detection) ? detection?.task_run_id : null
            if (!liveRunId) {
                cache.scanTickerRunId = null
                cache.disposables.dispose('scan-step-ticker')
                return
            }
            if (cache.scanTickerRunId === liveRunId) {
                return
            }
            cache.scanTickerRunId = liveRunId
            actions.resetScanSteps()
            cache.disposables.add(() => {
                const interval = setInterval(() => actions.advanceScanStep(), SCAN_STEP_INTERVAL_MS)
                return () => clearInterval(interval)
            }, 'scan-step-ticker')
        }
        // While the handle points at a live run, keep a poll scheduled; scheduled on success
        // AND failure so one transient fetch error doesn't freeze the progress view.
        const scheduleDetectionBasedRunPoll = (): void => {
            if (!values.detectionBasedRun) {
                return
            }
            cache.disposables.add(() => {
                const timeout = setTimeout(() => actions.loadDetectionBasedRun(), DETECTION_BASED_RUN_POLL_INTERVAL_MS)
                return () => clearTimeout(timeout)
            }, 'detection-based-run-poll')
        }
        return {
            setSelectedRepository: () => {
                cache.disposables.dispose('detection-based-run-poll')
                syncScanStepTicker()
            },
            setStep: () => syncScanStepTicker(),
            continueFromRepository: () => {
                // A repository that was already scanned (or is being scanned) goes straight to
                // its results; only unscanned and failed ones trigger a fresh scan.
                const detection = values.selectedDetection
                if (detection && (isLiveDetection(detection) || detection.report)) {
                    actions.setStep('project')
                } else {
                    actions.startDetection()
                }
            },
            startDetection: async () => {
                const { selectedRepositoryFull, currentProjectId } = values
                if (!selectedRepositoryFull || !currentProjectId) {
                    actions.startDetectionFailure()
                    return
                }
                try {
                    await api.create('api/wizard/repository_detection', {
                        project_id: currentProjectId,
                        repository: selectedRepositoryFull,
                        kind: SOURCE_MAPS_DETECTION_KIND,
                    })
                    actions.startDetectionSuccess()
                } catch (e) {
                    const detail = e instanceof ApiError ? e.detail : null
                    lemonToast.error(detail || 'Could not start the scan. Try again.')
                    actions.startDetectionFailure()
                }
            },
            startDetectionSuccess: () => {
                // The trigger stamps the new run onto the row, so this reload flips the row to
                // "running" and kicks off polling.
                actions.loadDetections()
            },
            loadDetectionsSuccess: () => {
                // A scan can outlive the modal. On the first load after (re)opening, jump
                // straight to the running scan so its progress is visible without re-picking
                // the account and repository.
                if (!cache.didAutoResume) {
                    cache.didAutoResume = true
                    const liveDetection = values.detections.find((detection) => isLiveDetection(detection))
                    if (liveDetection && values.step === 'intro') {
                        const slash = liveDetection.repository.indexOf('/')
                        const owner = slash > 0 ? liveDetection.repository.slice(0, slash) : null
                        const integration = owner
                            ? values.githubIntegrations.find((candidate) => candidate.config?.account?.name === owner)
                            : undefined
                        if (integration) {
                            actions.setSelectedIntegrationId(integration.id)
                            actions.setSelectedRepository(liveDetection.repository.slice(slash + 1))
                        } else {
                            actions.setSelectedRepository(liveDetection.repository)
                        }
                        actions.setStep('project')
                    }
                }
                const anyLive = values.detections.some((detection) => isLiveDetection(detection))
                if (anyLive) {
                    cache.disposables.add(() => {
                        const timeout = setTimeout(() => actions.loadDetections(), DETECTIONS_POLL_INTERVAL_MS)
                        return () => clearTimeout(timeout)
                    }, 'detections-poll')
                } else {
                    cache.disposables.dispose('detections-poll')
                }
                syncScanStepTicker()
            },
            startDetectionBasedRun: async ({ project }) => {
                const { selectedRepositoryFull, currentProjectId } = values
                if (!selectedRepositoryFull || !currentProjectId || !project.variant) {
                    actions.startDetectionBasedRunFailure()
                    return
                }
                try {
                    // The variant is not sent: the backend re-reads it from the stored detection
                    // report, so a run can only target what a scan actually found.
                    const response = await api.create<{ task_id: string; run_id: string; status: string }>(
                        'api/wizard/detection_based_cloud_run',
                        {
                            project_id: currentProjectId,
                            repository: selectedRepositoryFull,
                            kind: SOURCE_MAPS_DETECTION_KIND,
                            selected_path: project.path,
                        }
                    )
                    actions.startDetectionBasedRunSuccess({
                        taskId: response.task_id,
                        runId: response.run_id,
                        path: project.path,
                    })
                } catch (e) {
                    const detail = e instanceof ApiError ? e.detail : null
                    lemonToast.error(detail || 'Could not start the setup run. Try again.')
                    actions.startDetectionBasedRunFailure()
                }
            },
            startDetectionBasedRunSuccess: () => {
                actions.loadDetectionBasedRun()
            },
            loadDetectionBasedRunSuccess: () => {
                if (values.isDetectionBasedRunLive) {
                    scheduleDetectionBasedRunPoll()
                } else {
                    cache.disposables.dispose('detection-based-run-poll')
                }
            },
            loadDetectionBasedRunFailure: () => scheduleDetectionBasedRunPoll(),
            dismissDetectionBasedRun: () => {
                cache.disposables.dispose('detection-based-run-poll')
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadIntegrations()
        actions.loadDetections()
    }),
])
