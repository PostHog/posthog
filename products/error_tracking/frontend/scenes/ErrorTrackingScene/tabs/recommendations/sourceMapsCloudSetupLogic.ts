export const SOURCE_MAPS_DETECTION_KIND = 'error-tracking-source-maps'

const DETECTIONS_POLL_INTERVAL_MS = 1000

// 'intro' is the modal's default view (hero, account and repository pickers, and the manual
// command); the other two render as the stepper.
export type CloudSetupStep = 'intro' | 'project' | 'run'

// Purely cosmetic reassurance while a scan runs; not tied to what the sandbox is actually
// doing. Advances every SCAN_STEP_INTERVAL_MS and parks on the last entry.
export const SCAN_STEPS = [
    'Reserving a sandbox...',
    'Cloning your repository...',
    'Reading the file tree...',
    'Scanning source files...',
    'Looking for project manifests...',
    'Detecting frameworks...',
    'Inspecting build configs...',
    'Checking for monorepo workspaces...',
    'Looking for an existing PostHog setup...',
    'Checking how source maps are generated...',
    'Collecting candidate projects...',
    'Double-checking the results...',
    'Writing up the report...',
    'Almost there...',
    'Finalizing...',
]

const SCAN_STEP_INTERVAL_MS = 3000

// The run step is a placeholder until the cloud wizard run endpoint exists: it pretends to
// work for MOCK_RUN_DURATION_MS while these rotate, then links to the repository's pull
// request list instead of a real pull request.
export const MOCK_RUN_STEPS = ['Briefing the agent...', 'Applying the setup...', 'Opening a pull request...']

const MOCK_RUN_STEP_INTERVAL_MS = 1600
const MOCK_RUN_DURATION_MS = 5000

// TaskRun statuses that mean a scan is running right now; mirrors the trigger endpoint's
// concurrency gate, which 409s while the stamped run is in one of these.
const LIVE_TASK_RUN_STATUSES = ['not_started', 'queued', 'in_progress']

// Handwritten because the root /api/wizard viewset has no generated client — same
// precedent as wizardCloudRunLogic's cloud_run call. Shapes mirror
// SetupWizardRepositoryDetectionStatusSerializer and the wizard's detection report.
export interface DetectedProject {
    path: string
    framework: string
    variant: string | null
    has_posthog: boolean
    instrumentable: boolean
    reason?: string
}

export interface DetectionReport {
    repo_type: 'monorepo' | 'single'
    projects: DetectedProject[]
}

export interface RepositoryDetection {
    repository: string
    kind: string
    task_run_id: string | null
    task_run_status: string | null
    report: DetectionReport | null
    error: { type: string; message: string } | null
    updated_at: string
}

export function isLiveDetection(detection: RepositoryDetection | null): boolean {
    return !!detection?.task_run_status && LIVE_TASK_RUN_STATUSES.includes(detection.task_run_status)
}

