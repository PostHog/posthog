import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { getCurrentTeamId } from 'lib/utils/getAppContext'

import { errorTrackingIssuesSummaryRegenerateCreate, errorTrackingIssuesSummaryRetrieve } from '../../generated/api'
import type {
    ErrorTrackingStoredIssueSummaryApi,
    ErrorTrackingIssueSummaryResponseApi,
} from '../../generated/api.schemas'
import { IssueSummaryStatusEnumApi } from '../../generated/api.schemas'

export interface IssueSummaryLogicProps {
    issueId: string
}

export type IssueSummaryFeedback = 'good' | 'bad'

export type IssueSummaryView = 'hidden' | 'generating' | 'timed_out' | 'failed' | 'ready'

export const ISSUE_SUMMARY_POLL_INTERVAL_MS = 2000
export const ISSUE_SUMMARY_POLL_TIMEOUT_MS = 20000

