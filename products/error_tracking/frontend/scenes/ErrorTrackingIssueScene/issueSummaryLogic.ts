export const issueSummaryLogic = kea<issueSummaryLogicType>([
    props({} as IssueSummaryLogicProps),
    key((props) => props.issueId),
    path((key) => ['products', 'error_tracking', 'scenes', 'ErrorTrackingIssueScene', 'issueSummaryLogic', key]),

    connect(() => ({
        values: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['dateRange', 'filterTestAccounts', 'filterGroup', 'searchQuery'],
        ],
        actions: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['setDateRange', 'setFilterTestAccounts', 'setFilterGroup', 'setSearchQuery'],
        ],
    })),

    actions({
        loadSummary: true,
        setLastSeen: (lastSeen: string) => ({ lastSeen }),
    }),

    loaders(({ values, props }) => ({
        summary: [
            null as ErrorTrackingIssueSummary | null,
            {
                loadSummary: async (_, breakpoint) => {
                    // A reset dispatches several filter changes in one tick. Debounce them into one query,
                    // then discard its response if a newer load supersedes it while it is in flight.
                    await breakpoint(100)
                    const response = await api.query(
                        errorTrackingIssueQuery({
                            issueId: props.issueId,
                            dateRange: values.dateRange,
                            filterTestAccounts: values.filterTestAccounts,
                            filterGroup: values.filterGroup,
                            searchQuery: values.searchQuery,
                            volumeResolution: ERROR_TRACKING_DETAILS_RESOLUTION,
                            withAggregations: true,
                            withFirstEvent: true,
                            withLastEvent: true,
                        }),
                        { refresh: 'blocking' }
                    )
                    breakpoint()
                    if (!response.results.length) {
                        return null
                    }
                    return toErrorTrackingIssueSummary(response.results[0])
                },
            },
        ],
    })),

    reducers({
        lastSeen: [
            null as Dayjs | null,
            {
                setLastSeen: (prevLastSeen, { lastSeen }) => {
                    const lastSeenDayjs = dayjs(lastSeen)
                    if (!prevLastSeen || prevLastSeen.isBefore(lastSeenDayjs)) {
                        return lastSeenDayjs
                    }
                    return prevLastSeen
                },
            },
        ],
    }),

    selectors({
        aggregations: [(s) => [s.summary], (summary: ErrorTrackingIssueSummary | null) => summary?.aggregations],
    }),

    listeners(({ actions }) => ({
        setDateRange: actions.loadSummary,
        setFilterGroup: actions.loadSummary,
        setFilterTestAccounts: actions.loadSummary,
        setSearchQuery: actions.loadSummary,
        loadSummarySuccess: ({ summary }) => {
            if (summary && summary.last_seen) {
                actions.setLastSeen(summary.last_seen)
            }
        },
    })),
])

export function toErrorTrackingIssueSummary(
    summary: Pick<ErrorTrackingIssue, 'first_seen' | 'last_seen' | 'first_event' | 'last_event' | 'aggregations'>
): ErrorTrackingIssueSummary | null {
    if (!summary.aggregations) {
        return null
    }

    return {
        first_seen: summary.first_seen,
        last_seen: summary.last_seen,
        first_event_uuid: summary.first_event?.uuid,
        last_event_uuid: summary.last_event?.uuid,
        aggregations: summary.aggregations,
    }
}
