import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { dayjs } from 'lib/dayjs'
import { getCurrentTeamId } from 'lib/utils/getAppContext'

import { errorTrackingIssuesSummaryRetrieve } from '../../generated/api'
import type {
    ErrorTrackingStoredIssueSummaryApi,
    ErrorTrackingIssueSummaryResponseApi,
} from '../../generated/api.schemas'
import { issuePaneSectionsLogic } from './issuePaneSectionsLogic'

export interface IssueSummaryLogicProps {
    issueId: string
    firstSeen: string | null
}

export type IssueSummaryFeedback = 'good' | 'bad'

export type IssueSummaryView =
    | 'hidden'
    | 'failed'
    | 'ready'
    | 'writing'
    | 'not_generated'
    | 'ai_not_approved'
    | 'restricted'

// The issue-created workflow writes the summary soon after the first exception. Until this much time has passed, a
// missing summary is most likely still being written, not skipped.
const SUMMARY_WRITE_WINDOW_MINUTES = 5

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface issueSummaryLogicValues {
    summaryOpen: boolean // issuePaneSectionsLogic
    feedback: IssueSummaryFeedback | null
    loadFailed: boolean
    summary: ErrorTrackingStoredIssueSummaryApi | null
    summaryResponse: ErrorTrackingIssueSummaryResponseApi | null
    summaryResponseLoading: boolean
    view: IssueSummaryView
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface issueSummaryLogicActions {
    loadSummary: () => any
    loadSummaryFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSummarySuccess: (
        summaryResponse: ErrorTrackingIssueSummaryResponseApi | null,
        payload?: any
    ) => {
        summaryResponse: ErrorTrackingIssueSummaryResponseApi | null
        payload?: any
    }
    markLoadFailed: () => {
        value: true
    }
    sendFeedback: (feedback: IssueSummaryFeedback) => {
        feedback: IssueSummaryFeedback
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface issueSummaryLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        summary: (
            summaryResponse: ErrorTrackingIssueSummaryResponseApi | null
        ) => ErrorTrackingStoredIssueSummaryApi | null
        view: (
            summaryResponse: ErrorTrackingIssueSummaryResponseApi | null,
            loadFailed: boolean,
            firstSeen: string | null
        ) => IssueSummaryView
    }
}

export type issueSummaryLogicType = MakeLogicType<
    issueSummaryLogicValues,
    issueSummaryLogicActions,
    IssueSummaryLogicProps,
    issueSummaryLogicMeta
>

export const issueSummaryLogic = kea<issueSummaryLogicType>([
    props({ firstSeen: null } as IssueSummaryLogicProps),
    key((props) => props.issueId),
    path((key) => ['products', 'error_tracking', 'scenes', 'ErrorTrackingIssueScene', 'issueSummaryLogic', key]),
    connect(() => ({ values: [issuePaneSectionsLogic, ['summaryOpen']] })),
    actions({
        markLoadFailed: true,
        sendFeedback: (feedback: IssueSummaryFeedback) => ({ feedback }),
    }),
    loaders(({ props, actions, values }) => ({
        summaryResponse: [
            null as ErrorTrackingIssueSummaryResponseApi | null,
            {
                loadSummary: async (): Promise<ErrorTrackingIssueSummaryResponseApi | null> => {
                    try {
                        return await errorTrackingIssuesSummaryRetrieve(getCurrentTeamId().toString(), props.issueId)
                    } catch (error) {
                        // The section shows its own retry line, so a failed read must not also raise the loader toast.
                        console.error('Failed to load the issue summary:', error)
                        actions.markLoadFailed()
                        return values.summaryResponse
                    }
                },
            },
        ],
    })),
    reducers({
        loadFailed: [
            false,
            {
                // The loader dispatches `markLoadFailed` before its own success action, so reset on the request.
                loadSummary: () => false,
                markLoadFailed: () => true,
            },
        ],
        feedback: [
            null as IssueSummaryFeedback | null,
            {
                sendFeedback: (_, { feedback }) => feedback,
            },
        ],
    }),
    selectors({
        summary: [
            (s) => [s.summaryResponse],
            (summaryResponse: ErrorTrackingIssueSummaryResponseApi | null): ErrorTrackingStoredIssueSummaryApi | null =>
                summaryResponse?.summary ?? null,
        ],
        view: [
            (s, p) => [s.summaryResponse, s.loadFailed, p.firstSeen],
            (
                summaryResponse: ErrorTrackingIssueSummaryResponseApi | null,
                loadFailed: boolean,
                firstSeen: string | null
            ): IssueSummaryView => {
                if (summaryResponse?.summary) {
                    return 'ready'
                }
                if (loadFailed) {
                    // Only the backend knows whether summaries are on for the project. Until an answer says they are,
                    // a failure shows nothing, so a project without them never sees a summary row.
                    return summaryResponse !== null && summaryResponse.reason !== 'disabled' ? 'failed' : 'hidden'
                }
                if (summaryResponse?.status === 'not_generated') {
                    const isNew =
                        firstSeen !== null &&
                        dayjs().diff(dayjs(firstSeen), 'minute', true) < SUMMARY_WRITE_WINDOW_MINUTES
                    return isNew ? 'writing' : 'not_generated'
                }
                if (summaryResponse?.reason === 'ai_not_approved' || summaryResponse?.reason === 'restricted') {
                    return summaryResponse.reason
                }
                // Before the first answer, and when summaries are off for the project, which is most teams. A
                // line here would flash on every issue page, or tell people about a feature they do not have.
                return 'hidden'
            },
        ],
    }),
    listeners(({ values, cache, props }) => ({
        loadSummarySuccess: () => {
            const summary = values.summary
            if (summary && cache.viewedGeneratedAt !== summary.generated_at) {
                cache.viewedGeneratedAt = summary.generated_at
                posthog.capture('error_tracking_issue_summary_viewed', {
                    issue_id: props.issueId,
                    // A person can keep the summary closed, so the event alone does not mean they read it.
                    summary_open: values.summaryOpen,
                    category: summary.category,
                    model: summary.model,
                    generated_at: summary.generated_at,
                })
            }
        },
        sendFeedback: ({ feedback }) => {
            posthog.capture('error_tracking_issue_summary_feedback', {
                issue_id: props.issueId,
                feedback,
                category: values.summary?.category ?? null,
                model: values.summary?.model ?? null,
                generated_at: values.summary?.generated_at ?? null,
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSummary()
    }),
])
