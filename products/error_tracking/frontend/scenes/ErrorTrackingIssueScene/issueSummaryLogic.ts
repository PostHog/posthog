export type issueSummaryLogicType = MakeLogicType<
    issueSummaryLogicValues,
    issueSummaryLogicActions,
    IssueSummaryLogicProps,
    issueSummaryLogicMeta
>

export const issueSummaryLogic = kea<issueSummaryLogicType>([
    props({} as IssueSummaryLogicProps),
    key((props) => props.issueId),
    path((key) => ['products', 'error_tracking', 'scenes', 'ErrorTrackingIssueScene', 'issueSummaryLogic', key]),
    actions({
        markLoadFailed: true,
        startPolling: true,
        stopPolling: true,
        pollTimedOut: true,
        sendFeedback: (feedback: IssueSummaryFeedback) => ({ feedback }),
    }),
    loaders(({ props, actions, values }) => ({
        summaryResponse: [
            null as ErrorTrackingIssueSummaryResponseApi | null,
            {
                loadSummary: async (): Promise<ErrorTrackingIssueSummaryResponseApi | null> => {
                    try {
                        return await errorTrackingIssuesSummaryRetrieve(getCurrentTeamId().toString(), props.issueId)
                    } catch (error) {
                        // The section shows its own retry line, so a failed read must not also raise the loader toast.
                        console.error('Failed to load the issue summary:', error)
                        actions.markLoadFailed()
                        return values.summaryResponse
                    }
                },
                regenerateSummary: async (): Promise<ErrorTrackingIssueSummaryResponseApi | null> => {
                    return await errorTrackingIssuesSummaryRegenerateCreate(
                        getCurrentTeamId().toString(),
                        props.issueId
                    )
                },
            },
        ],
    })),
    reducers({
        loadFailed: [
            false,
            {
                // The loader dispatches `markLoadFailed` before its own success action, so reset on the request.
                loadSummary: () => false,
                markLoadFailed: () => true,
            },
        ],
        timedOut: [
            false,
            {
                pollTimedOut: () => true,
                loadSummary: () => false,
            },
        ],
        polling: [
            false,
            {
                startPolling: () => true,
                stopPolling: () => false,
            },
        ],
        // The `generated_at` of the summary a regeneration replaces. Reads return that summary as ready
        // until the new one lands, so polling compares against it.
        replacedGeneratedAt: [
            null as string | null,
            {
                regenerateSummarySuccess: (_, { summaryResponse }) =>
                    summaryResponse?.status === IssueSummaryStatusEnumApi.Generating
                        ? (summaryResponse.summary?.generated_at ?? null)
                        : null,
                stopPolling: () => null,
            },
        ],
        regenerating: [
            false,
            {
                regenerateSummary: () => true,
                regenerateSummarySuccess: (_, { summaryResponse }) =>
                    summaryResponse?.status === IssueSummaryStatusEnumApi.Generating,
                regenerateSummaryFailure: () => false,
                stopPolling: () => false,
            },
        ],
        feedback: [
            null as IssueSummaryFeedback | null,
            {
                sendFeedback: (_, { feedback }) => feedback,
                regenerateSummarySuccess: () => null,
            },
        ],
    }),
    selectors({
        summary: [
            (s) => [s.summaryResponse],
            (summaryResponse: ErrorTrackingIssueSummaryResponseApi | null): ErrorTrackingStoredIssueSummaryApi | null =>
                summaryResponse?.summary ?? null,
        ],
        awaitingSummary: [
            (s) => [s.summaryResponse, s.replacedGeneratedAt],
            (
                summaryResponse: ErrorTrackingIssueSummaryResponseApi | null,
                replacedGeneratedAt: string | null
            ): boolean =>
                summaryResponse?.status === IssueSummaryStatusEnumApi.Generating ||
                (replacedGeneratedAt !== null && summaryResponse?.summary?.generated_at === replacedGeneratedAt),
        ],
        view: [
            (s) => [s.summaryResponse, s.summary, s.loadFailed, s.timedOut],
            (
                summaryResponse: ErrorTrackingIssueSummaryResponseApi | null,
                summary: ErrorTrackingStoredIssueSummaryApi | null,
                loadFailed: boolean,
                timedOut: boolean
            ): IssueSummaryView => {
                if (summary) {
                    return 'ready'
                }
                if (loadFailed) {
                    return 'failed'
                }
                if (summaryResponse?.status === IssueSummaryStatusEnumApi.Generating) {
                    return timedOut ? 'timed_out' : 'generating'
                }
                // Before the first answer and when no summary will come. Most teams do not have summaries,
                // so a placeholder here would flash on every issue page.
                return 'hidden'
            },
        ],
    }),
    listeners(({ actions, values, cache, props }) => {
        // Each poll waits for the previous answer, so a slow endpoint never has requests piling up.
        const scheduleNextPoll = (): void => {
            cache.disposables.add(() => {
                const id = setTimeout(() => actions.loadSummary(), ISSUE_SUMMARY_POLL_INTERVAL_MS)
                return () => clearTimeout(id)
            }, 'summaryPoll')
        }
        return {
            startPolling: () => {
                cache.disposables.add(() => {
                    const id = setTimeout(() => actions.pollTimedOut(), ISSUE_SUMMARY_POLL_TIMEOUT_MS)
                    return () => clearTimeout(id)
                }, 'summaryPollDeadline')
            },
            stopPolling: () => {
                cache.disposables.dispose('summaryPoll')
                cache.disposables.dispose('summaryPollDeadline')
            },
            pollTimedOut: () => {
                // A regenerate whose inputs did not change keeps the same `generated_at`, so it always ends here.
                // Read `regenerating` first, because `stopPolling` resets it.
                if (values.regenerating && values.summary) {
                    lemonToast.info('No new summary yet. Check back later.')
                }
                actions.stopPolling()
            },
            markLoadFailed: () => {
                actions.stopPolling()
            },
            loadSummarySuccess: () => {
                if (values.loadFailed) {
                    return
                }
                if (values.awaitingSummary) {
                    // A poll sent before the deadline can answer after it. Only "Try again" starts a new cycle.
                    if (values.timedOut) {
                        return
                    }
                    // Starting again would also push the deadline back, so a poll that keeps answering
                    // `generating` would never time out.
                    if (!values.polling) {
                        actions.startPolling()
                    }
                    scheduleNextPoll()
                    return
                }
                actions.stopPolling()
                const summary = values.summary
                if (summary && cache.viewedGeneratedAt !== summary.generated_at) {
                    cache.viewedGeneratedAt = summary.generated_at
                    posthog.capture('error_tracking_issue_summary_viewed', {
                        issue_id: props.issueId,
                        category: summary.category,
                        model: summary.model,
                        generated_at: summary.generated_at,
                    })
                }
            },
            regenerateSummary: () => {
                posthog.capture('error_tracking_issue_summary_regenerated', { issue_id: props.issueId })
            },
            regenerateSummarySuccess: ({ summaryResponse }) => {
                if (summaryResponse?.status === IssueSummaryStatusEnumApi.Generating) {
                    actions.startPolling()
                    scheduleNextPoll()
                } else if (summaryResponse?.summary) {
                    lemonToast.info('This summary is already up to date.')
                }
            },
            sendFeedback: ({ feedback }) => {
                posthog.capture('error_tracking_issue_summary_feedback', {
                    issue_id: props.issueId,
                    feedback,
                    category: values.summary?.category ?? null,
                    model: values.summary?.model ?? null,
                    generated_at: values.summary?.generated_at ?? null,
                })
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadSummary()
    }),
])
