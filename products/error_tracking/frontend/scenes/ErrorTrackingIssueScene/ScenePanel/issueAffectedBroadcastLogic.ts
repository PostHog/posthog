export type issueAffectedBroadcastLogicType = MakeLogicType<
    issueAffectedBroadcastLogicValues,
    issueAffectedBroadcastLogicActions,
    IssueAffectedBroadcastLogicProps,
    issueAffectedBroadcastLogicMeta
>

export const issueAffectedBroadcastLogic = kea<issueAffectedBroadcastLogicType>([
    path((issueId) => [
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingIssueScene',
        'ScenePanel',
        'issueAffectedBroadcastLogic',
        issueId,
    ]),
    props({} as IssueAffectedBroadcastLogicProps),
    key((props) => props.issueId),
    connect(() => ({ values: [teamLogic, ['currentProjectId']] })),

    actions({
        openModal: true,
        openModalAfterResolve: true,
        closeModal: true,
        offerAfterResolve: true,
    }),

    reducers({
        isModalOpen: [
            false,
            {
                openModal: () => true,
                openModalAfterResolve: () => true,
                closeModal: () => false,
            },
        ],
        source: [
            SOURCE as string,
            {
                openModal: () => SOURCE,
                openModalAfterResolve: () => RESOLVED_SOURCE,
            },
        ],
        countFailed: [
            false,
            {
                loadAffectedCount: () => false,
                loadAffectedCountFailure: () => true,
            },
        ],
    }),

    loaders(({ props, values }) => ({
        sendWarnings: [
            [] as string[],
            {
                // The audience cohort doesn't exist until Continue, so only the sender problems apply here.
                loadSendWarnings: async () =>
                    await loadMessageAudienceWarnings({ properties: [], source: SOURCE }, 'broadcast'),
            },
        ],
        affectedCount: [
            null as AffectedPeopleCount | null,
            {
                loadAffectedCount: async () => {
                    const response = await hogqlQuery(affectedPeopleQuery(props.issueId, 'count'))
                    const [people, withEmail] = (response.results?.[0] ?? [0, 0]) as [number, number]
                    return { people, withEmail }
                },
            },
        ],
        audienceCohort: [
            null as CohortApi | null,
            {
                createAudience: async () => {
                    const issueName = props.issueName || 'this issue'
                    return await cohortsCreate(String(values.currentProjectId), {
                        name: truncate(`People affected by ${issueName}`, MAX_NAME_LENGTH),
                        is_static: true,
                        query: { kind: NodeKind.HogQLQuery, query: affectedPeopleQuery(props.issueId, 'people') },
                    })
                },
            },
        ],
    })),

    listeners(({ actions, props, values, cache }) => ({
        openModal: () => {
            // The click on the entry point, before any outcome, so abandoned attempts count too.
            captureMessageAudienceClicked(SOURCE, 'broadcast')
            actions.loadAffectedCount()
            actions.loadSendWarnings()
        },
        openModalAfterResolve: () => {
            captureMessageAudienceClicked(RESOLVED_SOURCE, 'broadcast')
            actions.loadAffectedCount()
            actions.loadSendWarnings()
        },
        offerAfterResolve: () => {
            if (messageAudienceAccessDisabledReason()) {
                return
            }
            cache.offerOnCount = true
            actions.loadAffectedCount()
        },
        loadAffectedCountSuccess: ({ affectedCount }) => {
            if (!cache.offerOnCount) {
                return
            }
            cache.offerOnCount = false
            if (!affectedCount.withEmail) {
                return
            }
            lemonToast.success(
                `Issue resolved. ${pluralize(affectedCount.withEmail, 'person', 'people')} with an email address hit it in the last ${AFFECTED_LOOKBACK_DAYS} days.`,
                {
                    // The default id is a hash of the message, so two issues with the same count would share one toast.
                    toastId: `issue-resolved-${props.issueId}`,
                    button: {
                        label: "Tell them it's fixed",
                        dataAttr: 'issue-resolved-broadcast',
                        action: () => issueAffectedBroadcastLogic.findMounted(props)?.actions.openModalAfterResolve(),
                    },
                }
            )
        },
        loadAffectedCountFailure: () => {
            cache.offerOnCount = false
        },
        createAudienceSuccess: ({ audienceCohort }) => {
            if (!audienceCohort) {
                return
            }
            actions.closeModal()
            router.actions.push(
                messageAudienceUrl(
                    {
                        properties: cohortAudienceProperties(audienceCohort),
                        source: values.source,
                        broadcastName: truncate(`We fixed ${props.issueName || 'an error'}`, MAX_NAME_LENGTH),
                        broadcastEmail: draftMessage({ kind: 'issue_fixed' }),
                        draftSource: { source: 'error_tracking', source_id: props.issueId },
                    },
                    'broadcast'
                )
            )
        },
        createAudienceFailure: () => {
            lemonToast.error("Couldn't save the people affected. Try again.")
        },
    })),
])
