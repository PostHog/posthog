import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import { truncate } from 'lib/utils/strings'
import { teamLogic } from 'scenes/teamLogic'

import { hogqlQuery } from '~/queries/query'
import { NodeKind } from '~/queries/schema/schema-general'
import { HogQLQueryString, hogql } from '~/queries/utils'

import { cohortsCreate } from 'products/cohorts/frontend/generated/api'
import type { CohortApi } from 'products/cohorts/frontend/generated/api.schemas'
import {
    captureMessageAudienceClicked,
    cohortAudienceProperties,
    messageAudienceUrl,
} from 'products/workflows/frontend/MessageAudience/messageAudience'

export const AFFECTED_LOOKBACK_DAYS = 30
const MAX_NAME_LENGTH = 200

export interface IssueAffectedBroadcastLogicProps {
    issueId: string
    issueName: string | null
}

export interface AffectedPeopleCount {
    people: number
    withEmail: number
}

export function affectedPeopleQuery(issueId: string, select: 'count' | 'people'): HogQLQueryString {
    const where = hogql`event = '$exception' AND issue_id = ${issueId} AND timestamp >= now() - toIntervalDay(${AFFECTED_LOOKBACK_DAYS})`
    return select === 'count'
        ? (`SELECT uniqExact(person_id), uniqExactIf(person_id, notEmpty(toString(person.properties.email))) FROM events WHERE ${where}` as HogQLQueryString)
        : (`SELECT DISTINCT person_id FROM events WHERE ${where}` as HogQLQueryString)
}

