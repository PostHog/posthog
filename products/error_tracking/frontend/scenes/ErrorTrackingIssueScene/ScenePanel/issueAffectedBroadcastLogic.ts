export const issueAffectedBroadcastLogic = kea<issueAffectedBroadcastLogicType>([
    path((issueId) => [
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingIssueScene',
        'ScenePanel',
        'issueAffectedBroadcastLogic',
        issueId,
    ]),
    props({} as IssueAffectedBroadcastLogicProps),
    key((props) => props.issueId),
    connect(() => ({ values: [teamLogic, ['currentProjectId']] })),

    actions({
        openModal: true,
        closeModal: true,
    }),

    reducers({
        isModalOpen: [
            false,
            {
                openModal: () => true,
                closeModal: () => false,
            },
        ],
        countFailed: [
            false,
            {
                loadAffectedCount: () => false,
                loadAffectedCountFailure: () => true,
            },
        ],
    }),

    loaders(({ props, values }) => ({
        affectedCount: [
            null as AffectedPeopleCount | null,
            {
                loadAffectedCount: async () => {
                    const response = await hogqlQuery(affectedPeopleQuery(props.issueId, 'count'))
                    const [people, withEmail] = (response.results?.[0] ?? [0, 0]) as [number, number]
                    return { people, withEmail }
                },
            },
        ],
        audienceCohort: [
            null as CohortApi | null,
            {
                createAudience: async () => {
                    const issueName = props.issueName || 'this issue'
                    return await cohortsCreate(String(values.currentProjectId), {
                        name: truncate(`People affected by ${issueName}`, MAX_NAME_LENGTH),
                        is_static: true,
                        query: { kind: NodeKind.HogQLQuery, query: affectedPeopleQuery(props.issueId, 'people') },
                    })
                },
            },
        ],
    })),

    listeners(({ actions, props }) => ({
        openModal: () => {
            actions.loadAffectedCount()
        },
        createAudienceSuccess: ({ audienceCohort }) => {
            if (!audienceCohort) {
                return
            }
            actions.closeModal()
            captureMessageAudienceClicked('error_tracking_affected', 'broadcast')
            router.actions.push(
                messageAudienceUrl(
                    {
                        properties: cohortAudienceProperties(audienceCohort),
                        source: 'error_tracking_affected',
                        broadcastName: truncate(`We fixed ${props.issueName || 'an error'}`, MAX_NAME_LENGTH),
                    },
                    'broadcast'
                )
            )
        },
        createAudienceFailure: () => {
            lemonToast.error("Couldn't save the people affected. Try again.")
        },
    })),
])
