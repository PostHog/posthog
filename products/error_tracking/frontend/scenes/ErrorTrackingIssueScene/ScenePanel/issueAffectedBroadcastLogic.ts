export const AFFECTED_LOOKBACK_DAYS = 30
// pinned: sent as the broadcast's entry_source and the click event's source, so renaming it splits the history
const SOURCE = 'error_tracking_affected'
const MAX_NAME_LENGTH = 200

export interface IssueAffectedBroadcastLogicProps {
    issueId: string
    issueName: string | null
}

export interface AffectedPeopleCount {
    people: number
    withEmail: number
}

export function affectedPeopleQuery(issueId: string, select: 'count' | 'people'): HogQLQueryString {
    const where = hogql`event = '$exception' AND issue_id = ${issueId} AND timestamp >= now() - toIntervalDay(${AFFECTED_LOOKBACK_DAYS})`
    return select === 'count'
        ? (`SELECT uniqExact(person_id), uniqExactIf(person_id, notEmpty(toString(person.properties.email))) FROM events WHERE ${where}` as HogQLQueryString)
        : (`SELECT DISTINCT person_id FROM events WHERE ${where}` as HogQLQueryString)
}

export async function countAffectedPeople(issueId: string): Promise<AffectedPeopleCount> {
    const response = await hogqlQuery(affectedPeopleQuery(issueId, 'count'))
    const [people, withEmail] = (response.results?.[0] ?? [0, 0]) as [number, number]
    return { people, withEmail }
}

export async function createAffectedPeopleCohort(
    projectId: string,
    { issueId, issueName }: IssueAffectedBroadcastLogicProps
): Promise<CohortApi> {
    return await cohortsCreate(projectId, {
        name: truncate(`People affected by ${issueName || 'this issue'}`, MAX_NAME_LENGTH),
        is_static: true,
        query: { kind: NodeKind.HogQLQuery, query: affectedPeopleQuery(issueId, 'people') },
    })
}

export function issueFixedAudience(
    cohort: CohortApi,
    { issueId, issueName }: IssueAffectedBroadcastLogicProps,
    source: string
): MessageAudience {
    return {
        properties: cohortAudienceProperties(cohort),
        source,
        broadcastName: truncate(`We fixed ${issueName || 'an error'}`, MAX_NAME_LENGTH),
        broadcastEmail: draftMessage({ kind: 'issue_fixed' }),
        draftSource: { source: 'error_tracking', source_id: issueId },
    }
}

