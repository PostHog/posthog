/**
 * Which kinds of linked data the issue's exceptions list requires, and how many exceptions have each.
 * The scene logic connects this one for its list query, so the counts only load once the issue page
 * asks for them with `requestSummary`.
 */
export const issueLinkedDataLogic = kea<issueLinkedDataLogicType>([
    path((key) => ['products', 'error_tracking', 'scenes', 'ErrorTrackingIssueScene', 'issueLinkedDataLogic', key]),
    props({} as IssueLinkedDataLogicProps),
    key((props) => props.issueId),

    connect(() => ({
        values: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['dateRange', 'filterTestAccounts', 'filterGroup', 'searchQuery'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['setDateRange', 'setFilterTestAccounts', 'setFilterGroup', 'setSearchQuery'],
        ],
    })),

    actions({
        clearRequiredLinks: true,
        requestSummary: true,
        setLinkRequired: (kind: ErrorTrackingLinkedDataKind, required: boolean) => ({ kind, required }),
    }),

    reducers({
        requiredLinks: [
            [] as ErrorTrackingLinkedDataKind[],
            {
                setLinkRequired: (state, { kind, required }) => {
                    const withoutKind = state.filter((existing) => existing !== kind)
                    return required ? [...withoutKind, kind] : withoutKind
                },
                clearRequiredLinks: () => [],
            },
        ],
        summaryRequested: [
            false,
            {
                requestSummary: () => true,
            },
        ],
    }),

    selectors({
        logsEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean =>
                !!featureFlags[FEATURE_FLAGS.LOGS_IN_ERROR_TRACKING] &&
                userHasAccess(AccessControlResourceType.Logs, AccessControlLevel.Viewer),
        ],
        linkedDataKinds: [
            (s) => [s.logsEnabled],
            (logsEnabled: boolean): ErrorTrackingLinkedDataKind[] =>
                logsEnabled ? ['recording', 'logs'] : ['recording'],
        ],
        source: [
            (s, p) => [p.issueId, s.filterTestAccounts, s.searchQuery, s.filterGroup, s.dateRange],
            (
                issueId: string,
                filterTestAccounts: boolean,
                searchQuery: string,
                filterGroup: UniversalFiltersGroup,
                dateRange: DateRange
            ): EventsQuery =>
                errorTrackingIssueEventsQuery({
                    issueId,
                    filterTestAccounts,
                    filterGroup,
                    searchQuery,
                    dateRange,
                    columns: ISSUE_EVENTS_COLUMNS,
                }),
        ],
    }),

    loaders(({ props, values }) => ({
        summary: [
            null as ErrorTrackingLinkedDataSummary | null,
            {
                loadSummary: async (_, breakpoint) => {
                    await breakpoint(100)
                    const response = await api.query(
                        errorTrackingLinkedDataSummaryQuery({
                            issueId: props.issueId,
                            source: values.source,
                            linkedData: values.linkedDataKinds,
                        })
                    )
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),

    listeners(({ actions, values }) => {
        const reloadIfRequested = (): void => {
            if (values.summaryRequested) {
                actions.loadSummary()
            }
        }
        return {
            requestSummary: () => actions.loadSummary(),
            setDateRange: reloadIfRequested,
            setFilterTestAccounts: reloadIfRequested,
            setFilterGroup: reloadIfRequested,
            setSearchQuery: reloadIfRequested,
        }
    }),
])
