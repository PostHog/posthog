import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { subscriptions } from 'kea-subscriptions'

import { ErrorEventType } from 'lib/components/Errors/types'

import {
    AnyResponseType,
    ErrorTrackingIssueEventsQuery,
    ErrorTrackingIssueEventsQueryResponse,
} from '~/queries/schema/schema-general'

import { eventsSourceLogic } from '../../components/EventsTable/eventsSourceLogic'

/** How many exceptions the list checks for linked logs on its own before it asks the user to continue. */
export const AUTO_CHECK_LIMIT = 10_000

export type LinkedLogsCheckStatus = 'checking' | 'paused'

export interface LinkedLogsCheckLogicProps {
    query: ErrorTrackingIssueEventsQuery
    queryKey: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface linkedLogsCheckLogicValues {
    canLoadNextData: boolean // eventsSourceLogic
    items: ErrorEventType[] // eventsSourceLogic
    itemsLoading: boolean // eventsSourceLogic
    response: AnyResponseType | null // eventsSourceLogic
    checkUntil: number
    checkedCount: number
    shouldCheckOlder: boolean
    status: LinkedLogsCheckStatus | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface linkedLogsCheckLogicActions {
    loadNextData: () => any // eventsSourceLogic
    checkOlderExceptions: () => {
        value: true
    }
    setCheckUntil: (checkUntil: number) => {
        checkUntil: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface linkedLogsCheckLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        checkedCount: (response: AnyResponseType | null) => number
        shouldCheckOlder: (
            items: ErrorEventType[],
            itemsLoading: boolean,
            canLoadNextData: boolean,
            checkedCount: number,
            checkUntil: number
        ) => boolean
        status: (
            items: ErrorEventType[],
            itemsLoading: boolean,
            canLoadNextData: boolean,
            checkedCount: number,
            shouldCheckOlder: boolean
        ) => LinkedLogsCheckStatus | null
    }
}

export type linkedLogsCheckLogicType = MakeLogicType<
    linkedLogsCheckLogicValues,
    linkedLogsCheckLogicActions,
    LinkedLogsCheckLogicProps,
    linkedLogsCheckLogicMeta
>

/**
 * A page that requires linked logs checks a bounded number of exceptions, so it can come back empty while older
 * exceptions are still unchecked. This logic loads the next page by itself until a page has rows or the list has
 * checked `AUTO_CHECK_LIMIT` exceptions, and then leaves the next step to the user.
 */
export const linkedLogsCheckLogic = kea<linkedLogsCheckLogicType>([
    path((key) => ['products', 'error_tracking', 'scenes', 'ErrorTrackingIssueScene', 'linkedLogsCheckLogic', key]),
    props({} as LinkedLogsCheckLogicProps),
    key((props) => props.queryKey),

    connect((props: LinkedLogsCheckLogicProps) => ({
        values: [eventsSourceLogic(props), ['canLoadNextData', 'items', 'itemsLoading', 'response']],
        actions: [eventsSourceLogic(props), ['loadNextData']],
    })),

    actions({
        checkOlderExceptions: true,
        setCheckUntil: (checkUntil: number) => ({ checkUntil }),
    }),

    reducers({
        checkUntil: [
            AUTO_CHECK_LIMIT,
            {
                setCheckUntil: (_, { checkUntil }) => checkUntil,
            },
        ],
    }),

    selectors({
        // The data node adds up the counts of the pages it merged.
        checkedCount: [
            (s) => [s.response],
            (response: AnyResponseType | null): number =>
                (response as ErrorTrackingIssueEventsQueryResponse | null)?.checkedCount ?? 0,
        ],
        shouldCheckOlder: [
            (s) => [s.items, s.itemsLoading, s.canLoadNextData, s.checkedCount, s.checkUntil],
            (
                items: ErrorEventType[],
                itemsLoading: boolean,
                canLoadNextData: boolean,
                checkedCount: number,
                checkUntil: number
            ): boolean =>
                items.length === 0 && !itemsLoading && canLoadNextData && checkedCount > 0 && checkedCount < checkUntil,
        ],
        status: [
            (s) => [s.items, s.itemsLoading, s.canLoadNextData, s.checkedCount, s.shouldCheckOlder],
            (
                items: ErrorEventType[],
                itemsLoading: boolean,
                canLoadNextData: boolean,
                checkedCount: number,
                shouldCheckOlder: boolean
            ): LinkedLogsCheckStatus | null => {
                // Only an empty page from a logs check has a count. The first page loads like any other list.
                if (items.length > 0 || checkedCount === 0) {
                    return null
                }
                if (itemsLoading || shouldCheckOlder) {
                    return 'checking'
                }
                return canLoadNextData ? 'paused' : null
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        checkOlderExceptions: () => {
            actions.setCheckUntil(values.checkedCount + AUTO_CHECK_LIMIT)
            actions.loadNextData()
        },
    })),

    subscriptions(({ actions, values }) => ({
        // Every loaded page replaces the response, so two empty pages in a row still trigger a third.
        response: () => {
            if (values.shouldCheckOlder) {
                actions.loadNextData()
            }
        },
    })),
])
