export const errorTrackingIssueSceneLogic = kea<errorTrackingIssueSceneLogicType>([
    path((key) => [
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingIssueScene',
        'errorTrackingIssueSceneLogic',
        key,
    ]),
    props({} as ErrorTrackingIssueSceneLogicProps),
    key((props) => props.id),

    // Components and other logics read the issue page state through this logic, so it re-exposes
    // each focused logic under the value and action names they already use.
    connect((props: ErrorTrackingIssueSceneLogicProps) => ({
        values: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['dateRange', 'filterTestAccounts', 'filterGroup', 'searchQuery'],
            issueDetailLogic({ issueId: props.id, fingerprint: props.fingerprint }),
            ['issue', 'issueLoading', 'firstSeen'],
            issueSummaryLogic({ issueId: props.id }),
            ['summary', 'summaryLoading', 'aggregations', 'lastSeen'],
            issueEventSelectionLogic({ issueId: props.id }),
            ['initialEvent', 'initialEventLoading', 'initialEventTimestamp', 'selectedEvent'],
            issueFingerprintsLogic({ issueId: props.id }),
            ['issueFingerprints', 'issueFingerprintsLoading'],
            issueSpikeEventsLogic({ issueId: props.id }),
            ['spikeEvents', 'spikeEventsLoading'],
            linkedReportsLogic({ issueId: props.id }),
            ['linkedReports', 'linkedReportsLoading'],
        ],
        actions: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['setDateRange', 'setFilterTestAccounts', 'setFilterGroup', 'setSearchQuery'],
            issueActionsLogic,
            [
                'updateIssueAssignee',
                'updateIssueStatus',
                'updateIssueSeverity',
                'updateIssueName',
                'updateIssueDescription',
                'mutationFailure',
                'splitIssueSuccess',
            ],
            issueDetailLogic({ issueId: props.id, fingerprint: props.fingerprint }),
            [
                'loadIssue',
                'loadIssueSuccess',
                'loadIssueFailure',
                'setIssue',
                'createExternalReference',
                'linkExternalReference',
                'updateAssignee',
                'updateStatus',
                'updateSeverity',
                'updateName',
                'updateDescription',
            ],
            issueSummaryLogic({ issueId: props.id }),
            ['loadSummary', 'loadSummarySuccess', 'setLastSeen'],
            issueEventSelectionLogic({ issueId: props.id }),
            ['loadInitialEvent', 'loadInitialEventSuccess', 'setInitialEventTimestamp', 'selectEvent'],
            issueFingerprintsLogic({ issueId: props.id }),
            ['loadIssueFingerprints', 'loadIssueFingerprintsSuccess'],
            issueSpikeEventsLogic({ issueId: props.id }),
            ['loadSpikeEvents'],
            linkedReportsLogic({ issueId: props.id }),
            ['loadLinkedReports'],
        ],
    })),

    actions({
        setMobileDetailOpen: (mobileDetailOpen: boolean) => ({ mobileDetailOpen }),
        setListDateRange: (dateRange: DateRange) => ({ dateRange }),
    }),

    reducers({
        mobileDetailOpen: [
            false as boolean,
            {
                setMobileDetailOpen: (_, { mobileDetailOpen }) => mobileDetailOpen,
            },
        ],
        listDateRange: [
            null as DateRange | null,
            {
                setListDateRange: (_, { dateRange }) => dateRange,
            },
        ],
    }),

    selectors(({ actions }) => ({
        breadcrumbs: [
            (s) => [s.issue, s.listDateRange, s.filterTestAccounts, s.filterGroup, s.searchQuery],
            (
                issue: ErrorTrackingRelationalIssue | null,
                listDateRange: DateRange | null,
                filterTestAccounts: boolean,
                filterGroup: UniversalFiltersGroup,
                searchQuery: string
            ): Breadcrumb[] => {
                const exceptionType: string = issue?.name || 'Issue'
                // Use the original list date range for back navigation
                const urlParams = updateFilterSearchParams(
                    {},
                    {
                        dateRange: listDateRange ?? DEFAULT_DATE_RANGE,
                        filterTestAccounts,
                        filterGroup,
                        searchQuery,
                    }
                )

                return [
                    {
                        key: Scene.ErrorTracking,
                        name: 'Error tracking',
                        path: urls.errorTracking(urlParams),
                        iconType: 'error_tracking',
                    },
                    {
                        key: [Scene.ErrorTrackingIssue, exceptionType],
                        name: exceptionType,
                        onRename: async (name: string) => actions.updateName(name),
                        iconType: 'error_tracking',
                    },
                ]
            },
        ],

        [SIDE_PANEL_CONTEXT_KEY]: [
            (_, p) => [p.id],
            (issueId: string): SidePanelSceneContext => {
                return {
                    activity_scope: ActivityScope.ERROR_TRACKING_ISSUE,
                    activity_item_id: issueId,
                }
            },
        ],
        issueId: [(_, p) => [p.id], (id: string) => id],

        // A real issue id is a UUID. The catch-all `/error_tracking/:id` route can capture a
        // legacy settings slug (e.g. `symbol_sets`), so the scene checks this to show a
        // not-found state instead of firing loaders that fail with "issue_id must be a valid UUID".
        issueIdValid: [(_, p) => [p.id], (id: string) => isUUIDLike(id)],

        eventsQuery: [
            (s) => [s.issueId, s.filterTestAccounts, s.searchQuery, s.filterGroup, s.dateRange],
            (
                issueId: string,
                filterTestAccounts: boolean,
                searchQuery: string,
                filterGroup: UniversalFiltersGroup,
                dateRange: DateRange
            ) =>
                errorTrackingIssueEventsQuery({
                    issueId,
                    filterTestAccounts,
                    filterGroup,
                    searchQuery,
                    dateRange,
                    columns: ['*', 'timestamp', 'person'],
                }),
            // Preserve the query identity when selector inputs are deep-equal to avoid remounting the events table.
            { resultEqualityCheck: objectsEqual },
        ],

        // The key is the kea key of eventsSourceLogic, whose dataNodeLogic is wired in connect()
        // once per key: it MUST change when the query content changes (that's how a new query
        // reaches the data layer) and must NOT change otherwise — every key change unmounts and
        // remounts the entire events table tree.
        eventsQueryKey: [
            (s) => [s.eventsQuery],
            (eventsQuery: import('~/queries/schema').EventsQuery): string => JSON.stringify(eventsQuery),
        ],

        maxContext: [
            (s) => [s.issue, s.issueId],
            (issue: ErrorTrackingRelationalIssue | null, issueId: string): MaxContextInput[] => {
                if (!issueId) {
                    return []
                }
                return [
                    createMaxContextHelpers.errorTrackingIssue({
                        id: issueId,
                        name: issue?.name ?? null,
                    }),
                ]
            },
        ],
    })),

    listeners(({ props, values, actions }) => {
        return {
            loadSummarySuccess: ({ summary }: { summary: ErrorTrackingIssueSummary | null }) => {
                if (summary && summary.last_seen) {
                    actions.setInitialEventTimestamp(summary.last_seen)
                } else {
                    actions.setInitialEventTimestamp(values.issue?.first_seen ?? null)
                }
            },
            loadIssueFailure: ({ errorObject: { status, data } }) => {
                if (status == 308 && 'issue_id' in data) {
                    router.actions.replace(urls.errorTrackingIssue(data.issue_id))
                }
            },
            mutationFailure: ({ mutationName, issueId }) => {
                if (mutationName === 'updateIssueSeverity' && issueId === props.id) {
                    actions.loadIssue()
                }
            },
            splitIssueSuccess: ({ id }) => {
                if (id === props.id) {
                    actions.loadIssue()
                    actions.loadSummary()
                    actions.loadIssueFingerprints()
                    actions.loadSpikeEvents()
                    eventsSourceLogic
                        .findMounted({ query: values.eventsQuery, queryKey: values.eventsQueryKey })
                        ?.actions.loadData('force_blocking')
                }
            },
            selectEvent: ({ event }) => {
                if (event) {
                    router.actions.replace(
                        router.values.currentLocation.pathname,
                        {
                            ...router.values.searchParams,
                            timestamp: event.timestamp,
                        },
                        router.values.hashParams
                    )
                }
            },
            [issueActionsLogic.actionTypes.mutationSuccess]: ({ mutationName, issueId }) => {
                if (mutationName === 'createIssueCohort' && issueId === props.id) {
                    actions.loadIssue()
                }
            },
        }
    }),

    events(({ props, actions }) => ({
        afterMount: () => {
            // Skip the loaders for a non-UUID id: it is never a real issue, and each loader
            // would otherwise raise its own error toast on top of a blank page.
            if (!isUUIDLike(props.id)) {
                return
            }
            actions.loadIssue()
            actions.setInitialEventTimestamp(props.timestamp ?? null)
            actions.loadSummary()
            actions.loadIssueFingerprints()
            actions.loadSpikeEvents()
            actions.loadLinkedReports()
            globalSetupLogic.findMounted()?.actions.markTaskAsCompleted(SetupTaskId.ViewFirstError)
        },
    })),

    urlToAction(({ actions, values }) => {
        return {
            '**/error_tracking/:id': (_, params) => {
                if (values.listDateRange == null) {
                    actions.setListDateRange(params.dateRange ?? DEFAULT_DATE_RANGE)
                }
                triggerFilterActions(params, values, actions)
            },
        }
    }),

    actionToUrl(({ values }) => {
        const buildURL = (): ReturnType<typeof syncSearchParams> =>
            syncSearchParams(router, (params: Params) => {
                updateFilterSearchParams(params, values)
                delete params.tab
                return params
            })

        return {
            setDateRange: buildURL,
            setFilterGroup: buildURL,
            setSearchQuery: buildURL,
            setFilterTestAccounts: buildURL,
        }
    }),
])
