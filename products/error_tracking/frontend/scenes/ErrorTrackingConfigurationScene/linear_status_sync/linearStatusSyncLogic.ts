import { MakeLogicType, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { integrationsLogic } from 'lib/integrations/integrationsLogic'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { getCurrentTeamId } from 'lib/utils/getAppContext'

import { IntegrationType } from '~/types'

import {
    errorTrackingSettingsRetrieveSettingsRetrieve,
    errorTrackingSettingsUpdateSettingsPartialUpdate,
} from '../../../generated/api'
import type { ErrorTrackingSettingsApi } from '../../../generated/api.schemas'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface linearStatusSyncLogicValues {
    integrations: IntegrationType[] | null // integrationsLogic
    linearIntegrations: IntegrationType[] // integrationsLogic
    linearStatusSyncEnabled: boolean | null
    settings: ErrorTrackingSettingsApi | null
    settingsLoadFailed: boolean
    settingsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface linearStatusSyncLogicActions {
    loadSettings: () => any
    loadSettingsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSettingsSuccess: (
        settings: ErrorTrackingSettingsApi,
        payload?: any
    ) => {
        settings: ErrorTrackingSettingsApi
        payload?: any
    }
    setLinearStatusSyncEnabled: (linearStatusSyncEnabled: boolean) => boolean
    setLinearStatusSyncEnabledFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    setLinearStatusSyncEnabledSuccess: (
        settings: ErrorTrackingSettingsApi,
        payload?: boolean
    ) => {
        settings: ErrorTrackingSettingsApi
        payload?: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface linearStatusSyncLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        linearStatusSyncEnabled: (settings: ErrorTrackingSettingsApi | null) => boolean | null
    }
}

export type linearStatusSyncLogicType = MakeLogicType<
    linearStatusSyncLogicValues,
    linearStatusSyncLogicActions,
    Record<string, any>,
    linearStatusSyncLogicMeta
>

export const linearStatusSyncLogic = kea<linearStatusSyncLogicType>([
    path([
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingConfigurationScene',
        'linear_status_sync',
        'linearStatusSyncLogic',
    ]),

    connect(() => ({
        values: [integrationsLogic, ['integrations', 'linearIntegrations']],
    })),

    loaders({
        settings: [
            null as ErrorTrackingSettingsApi | null,
            {
                loadSettings: async () => {
                    return await errorTrackingSettingsRetrieveSettingsRetrieve(getCurrentTeamId().toString())
                },
                setLinearStatusSyncEnabled: async (linearStatusSyncEnabled: boolean) => {
                    return await errorTrackingSettingsUpdateSettingsPartialUpdate(getCurrentTeamId().toString(), {
                        linear_status_sync_enabled: linearStatusSyncEnabled,
                    })
                },
            },
        ],
    }),

    reducers({
        settingsLoadFailed: [
            false,
            {
                loadSettings: () => false,
                loadSettingsFailure: () => true,
            },
        ],
    }),

    selectors({
        linearStatusSyncEnabled: [
            (s) => [s.settings],
            (settings: ErrorTrackingSettingsApi | null): boolean | null =>
                settings ? settings.linear_status_sync_enabled === true : null,
        ],
    }),

    listeners({
        setLinearStatusSyncEnabledSuccess: ({ settings }) => {
            const enabled = settings.linear_status_sync_enabled === true
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('error_tracking_linear_status_sync_toggled', { enabled })
            lemonToast.success(enabled ? 'Linear status sync turned on' : 'Linear status sync turned off')
        },
    }),

    afterMount(({ actions }) => {
        actions.loadSettings()
    }),
])
