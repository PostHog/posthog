export const autoResolveSettingsLogic = kea<autoResolveSettingsLogicType>([
    props({} as AutoResolveSettingsLogicProps),
    key(({ projectId }) => projectId),
    path((key) => [
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingConfigurationScene',
        'auto_resolve',
        'autoResolveSettingsLogic',
        key,
    ]),
    forms(({ props, actions, values }) => ({
        configForm: {
            defaults: { enabled: false, days: AUTO_RESOLVE_DEFAULT_DAYS } as AutoResolveForm,
            errors: ({ enabled, days }) => ({
                days:
                    enabled &&
                    (days === null ||
                        !Number.isInteger(days) ||
                        days < AUTO_RESOLVE_MIN_DAYS ||
                        days > AUTO_RESOLVE_MAX_DAYS)
                        ? `Enter a whole number of days from ${AUTO_RESOLVE_MIN_DAYS} to ${AUTO_RESOLVE_MAX_DAYS}`
                        : undefined,
            }),
            submit: async ({ enabled, days }, breakpoint): Promise<void> => {
                if (!values.hasChanges || errorTrackingEditAccessDisabledReason()) {
                    return
                }

                const previousDays = values.settings?.auto_resolve_after_days ?? null
                const nextDays = enabled ? days : null
                const updated = await api.errorTrackingSettingsUpdateSettingsPartialUpdate(props.projectId, {
                    auto_resolve_after_days: nextDays,
                })
                posthog.capture('error_tracking_auto_resolve_setting_changed', {
                    project_id: props.projectId,
                    previous_days: previousDays,
                    days: updated.auto_resolve_after_days ?? null,
                })
                breakpoint()
                actions.loadAutoResolveSettingsSuccess(updated)
                lemonToast.success('Auto-resolve settings saved')
            },
        },
    })),
    loaders(({ props }) => ({
        settings: [
            null as ErrorTrackingSettingsApi | null,
            {
                loadAutoResolveSettings: async (): Promise<ErrorTrackingSettingsApi> =>
                    api.errorTrackingSettingsRetrieveSettingsRetrieve(props.projectId),
            },
        ],
    })),
    reducers({
        settingsLoadFailed: [
            false,
            { loadAutoResolveSettingsFailure: () => true, loadAutoResolveSettingsSuccess: () => false },
        ],
    }),
    selectors({
        hasChanges: [
            (s) => [s.settings, s.configForm],
            (settings: autoResolveSettingsLogicValues['settings'], { enabled, days }): boolean => {
                if (!settings) {
                    return false
                }
                const savedDays = settings.auto_resolve_after_days ?? null
                return enabled ? savedDays === null || days !== savedDays : savedDays !== null
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        loadAutoResolveSettingsSuccess: ({ settings }) => {
            const days = settings.auto_resolve_after_days ?? null
            actions.resetConfigForm({ enabled: days !== null, days: days ?? AUTO_RESOLVE_DEFAULT_DAYS })
        },
        submitConfigFormFailure: () => {
            if (!values.configFormHasErrors) {
                lemonToast.error("Couldn't save auto-resolve settings. Try again.")
            }
        },
    })),
    afterMount(({ actions, props }) => {
        if (props.projectId) {
            actions.loadAutoResolveSettings()
        }
    }),
])
