export const autoResolveConfigLogic = kea<autoResolveConfigLogicType>([
    path([
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingConfigurationScene',
        'auto_resolve',
        'autoResolveConfigLogic',
    ]),

    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    reducers({
        hasLoadedConfig: [
            false,
            {
                loadConfigSuccess: () => true,
            },
        ],
        configLoadFailed: [
            false,
            {
                loadConfig: () => false,
                loadConfigSuccess: () => false,
                loadConfigFailure: () => true,
            },
        ],
        previewCountFailed: [
            false,
            {
                loadPreviewCount: () => false,
                loadPreviewCountSuccess: () => false,
                loadPreviewCountFailure: () => true,
            },
        ],
    }),

    loaders(({ values }) => ({
        config: [
            null as ErrorTrackingSettingsApi | null,
            {
                loadConfig: async () => {
                    return await errorTrackingSettingsRetrieveSettingsRetrieve(String(values.currentTeamId))
                },
            },
        ],
        previewCount: [
            null as number | null,
            {
                loadPreviewCount: async ({ days }: { days: number }, breakpoint) => {
                    await breakpoint(PREVIEW_DEBOUNCE_MS)
                    const response = await errorTrackingSettingsAutoResolvePreviewRetrieve(
                        String(values.currentTeamId),
                        { days }
                    )
                    breakpoint()
                    return response.count
                },
            },
        ],
    })),

    selectors({
        savedDays: [
            (s) => [s.config],
            (config: ErrorTrackingSettingsApi | null): number | null => config?.auto_resolve_after_days ?? null,
        ],
    }),

    forms(({ actions, values }) => ({
        configForm: {
            defaults: { enabled: false, days: AUTO_RESOLVE_DEFAULT_DAYS } as AutoResolveConfigForm,
            errors: ({ enabled, days }) => ({
                days:
                    enabled && !isValidAutoResolveDays(days)
                        ? `Enter a whole number of days from ${AUTO_RESOLVE_MIN_DAYS} to ${AUTO_RESOLVE_MAX_DAYS}`
                        : undefined,
            }),
            submit: async ({ enabled, days }) => {
                const nextDays = enabled ? days : null
                const previousDays = values.savedDays
                try {
                    const updated = await errorTrackingSettingsUpdateSettingsPartialUpdate(
                        String(values.currentTeamId),
                        { auto_resolve_after_days: nextDays }
                    )
                    const event = autoResolveChangeEvent(previousDays, nextDays)
                    if (event) {
                        posthog.capture(event, {
                            days: nextDays ?? previousDays,
                            previous_days: previousDays,
                            preview_count: values.previewCount,
                        })
                    }
                    actions.loadConfigSuccess(updated)
                    lemonToast.success('Auto-resolve settings saved')
                } catch (e) {
                    lemonToast.error('Couldn’t save auto-resolve settings. Try again.')
                    throw e
                }
            },
        },
    })),

    listeners(({ actions, values }) => ({
        loadConfigSuccess: ({ config }) => {
            const days = config?.auto_resolve_after_days ?? null
            actions.resetConfigForm({ enabled: days !== null, days: days ?? AUTO_RESOLVE_DEFAULT_DAYS })
            if (days !== null) {
                actions.loadPreviewCount({ days })
            }
        },
        setConfigFormValue: () => {
            const { enabled, days } = values.configForm
            if (enabled && isValidAutoResolveDays(days)) {
                actions.loadPreviewCount({ days })
            }
        },
    })),

    afterMount(({ actions, values }) => {
        if (!values.hasLoadedConfig) {
            actions.loadConfig()
        }
    }),
])
