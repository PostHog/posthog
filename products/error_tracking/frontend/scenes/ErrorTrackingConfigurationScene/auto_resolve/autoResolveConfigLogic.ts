export const autoResolveConfigLogic: LogicWrapper<autoResolveConfigLogicType> = kea<autoResolveConfigLogicType>([
    props({} as AutoResolveConfigLogicProps),
    key((props): number | string => props.teamId ?? 'unknown'),
    path((key) => [
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingConfigurationScene',
        'auto_resolve',
        'autoResolveConfigLogic',
        key,
    ]),

    reducers({
        configLoadFailed: [
            false,
            {
                loadConfig: () => false,
                loadConfigFailure: () => true,
                loadConfigSuccess: () => false,
            },
        ],
    }),

    loaders(({ props }) => ({
        config: [
            null as ErrorTrackingSettingsApi | null,
            {
                loadConfig: async (_ = undefined, breakpoint) => {
                    if (props.teamId === null) {
                        return null
                    }
                    const config = await api.errorTrackingSettingsRetrieveSettingsRetrieve(String(props.teamId))
                    breakpoint()
                    return config
                },
            },
        ],
    })),

    forms(({ actions, props, values }) => ({
        configForm: {
            defaults: DEFAULT_CONFIG,
            errors: ({ enabled, days }) => ({
                days:
                    enabled && (!Number.isInteger(days) || days < MIN_AUTO_RESOLVE_DAYS || days > MAX_AUTO_RESOLVE_DAYS)
                        ? `Enter a whole number of days from ${MIN_AUTO_RESOLVE_DAYS} to ${MAX_AUTO_RESOLVE_DAYS}`
                        : undefined,
            }),
            submit: async ({ enabled, days }, breakpoint) => {
                if (props.teamId === null || values.config === null) {
                    throw new Error('Load the auto-resolve settings before saving.')
                }
                const auto_resolve_after_days = enabled ? days : null
                const updated = await api.errorTrackingSettingsUpdateSettingsPartialUpdate(String(props.teamId), {
                    auto_resolve_after_days,
                })
                breakpoint()
                actions.loadConfigSuccess(updated)
                posthog.capture('error_tracking_auto_resolve_updated', { auto_resolve_after_days })
            },
        },
    })),

    listeners(({ actions }) => ({
        submitConfigFormSuccess: () => {
            lemonToast.success('Auto-resolve settings saved')
        },
        submitConfigFormFailure: () => {
            lemonToast.error('Failed to save auto-resolve settings')
        },
        loadConfigSuccess: ({ config }) => {
            if (config) {
                const days = config.auto_resolve_after_days
                actions.resetConfigForm({
                    enabled: days != null,
                    days: days ?? DEFAULT_AUTO_RESOLVE_DAYS,
                })
            }
        },
    })),

    afterMount(({ actions, props }) => {
        if (props.teamId !== null) {
            actions.loadConfig()
        }
    }),
])
