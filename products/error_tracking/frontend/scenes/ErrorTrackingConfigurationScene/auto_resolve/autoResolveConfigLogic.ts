export type autoResolveConfigLogicType = MakeLogicType<autoResolveConfigLogicValues, autoResolveConfigLogicActions>

export const autoResolveConfigLogic = kea<autoResolveConfigLogicType>([
    path([
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingConfigurationScene',
        'auto_resolve',
        'autoResolveConfigLogic',
    ]),

    reducers({
        hasLoadedConfig: [
            false,
            {
                loadConfigSuccess: () => true,
            },
        ],
    }),

    loaders({
        config: [
            null as ErrorTrackingSettingsApi | null,
            {
                loadConfig: async () => {
                    return await api.errorTrackingSettingsRetrieveSettingsRetrieve(
                        String(teamLogic.values.currentTeamId)
                    )
                },
            },
        ],
    }),

    forms(({ actions }) => ({
        configForm: {
            defaults: DEFAULT_CONFIG,
            errors: ({ enabled, days }) => ({
                days:
                    enabled && (!Number.isInteger(days) || days < MIN_AUTO_RESOLVE_DAYS || days > MAX_AUTO_RESOLVE_DAYS)
                        ? `Enter a whole number of days from ${MIN_AUTO_RESOLVE_DAYS} to ${MAX_AUTO_RESOLVE_DAYS}`
                        : undefined,
            }),
            submit: async ({ enabled, days }) => {
                const auto_resolve_after_days = enabled ? days : null
                try {
                    const updated = await api.errorTrackingSettingsUpdateSettingsPartialUpdate(
                        String(teamLogic.values.currentTeamId),
                        { auto_resolve_after_days }
                    )
                    actions.loadConfigSuccess(updated)
                    posthog.capture('error_tracking_auto_resolve_updated', { auto_resolve_after_days })
                    lemonToast.success('Auto-resolve settings saved')
                } catch (e) {
                    lemonToast.error('Failed to save auto-resolve settings')
                    throw e
                }
            },
        },
    })),

    listeners(({ actions }) => ({
        loadConfigSuccess: ({ config }) => {
            if (config) {
                const days = config.auto_resolve_after_days
                actions.resetConfigForm({
                    enabled: days != null,
                    days: days ?? DEFAULT_AUTO_RESOLVE_DAYS,
                })
            }
        },
    })),

    afterMount(({ actions, values }) => {
        if (!values.hasLoadedConfig) {
            actions.loadConfig()
        }
    }),
])
