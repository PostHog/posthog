export const severityRuleModalLogic = kea<severityRuleModalLogicType>([
    path([
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingConfigurationScene',
        'severity_rules',
        'severityRuleModalLogic',
    ]),

    actions({
        openModal: (rule?: ErrorTrackingSeverityRule) => ({ rule: rule ?? null }),
        closeModal: true,
        updateRule: (rule: EditableSeverityRule) => ({ rule }),
        updateSeverity: (severity: ErrorTrackingIssueSeverityRuleEnumApi) => ({ severity }),
        increaseDateRange: true,
    }),

    reducers({
        isOpen: [false, { openModal: () => true, closeModal: () => false }],
        rule: [
            emptyRule() as EditableSeverityRule,
            {
                openModal: (_: EditableSeverityRule, { rule }: { rule: ErrorTrackingSeverityRule | null }) =>
                    rule ?? emptyRule(),
                updateRule: (_: EditableSeverityRule, { rule }: { rule: EditableSeverityRule }) => rule,
                updateSeverity: (
                    state: EditableSeverityRule,
                    { severity }: { severity: ErrorTrackingIssueSeverityRuleEnumApi }
                ) => ({ ...state, severity }),
            },
        ],
        dateRange: [
            '-7d' as string,
            {
                openModal: () => '-7d',
                updateRule: () => '-7d',
                increaseDateRange: (state: string) => ({ '-7d': '-30d', '-30d': '-90d' })[state] ?? state,
            },
        ],
    }),

    loaders(({ values }) => ({
        matchResult: [
            null as { exceptionCount: number; issueCount: number } | null,
            {
                loadMatchCount: async () => {
                    const filters = values.rule.filters as UniversalFiltersGroup
                    const properties = (filters.values as AnyPropertyFilter[]) ?? []
                    if (properties.length === 0) {
                        return null
                    }
                    const response = (await api.query({
                        kind: NodeKind.EventsQuery,
                        event: '$exception',
                        select: ['count()', 'count(distinct issue_id)'],
                        after: values.dateRange,
                        tags: { productKey: ProductKey.ERROR_TRACKING },
                        fixedProperties: [{ type: filters.type ?? FilterLogicalOperator.And, values: properties }],
                    })) as Record<string, any>
                    return {
                        exceptionCount: response.results?.[0]?.[0] ?? 0,
                        issueCount: response.results?.[0]?.[1] ?? 0,
                    }
                },
                resetMatchCount: () => null,
            },
        ],
        saving: [
            false,
            {
                saveRule: async () => {
                    const rule = values.rule
                    if (rule.id === 'new') {
                        await api.errorTracking.createRule(ErrorTrackingRuleType.Severity, rule)
                    } else {
                        await api.errorTracking.updateRule(ErrorTrackingRuleType.Severity, rule)
                    }
                    return true
                },
            },
        ],
        deleting: [
            false,
            {
                deleteRule: async () => {
                    await api.errorTracking.deleteRule(ErrorTrackingRuleType.Severity, values.rule.id)
                    return true
                },
            },
        ],
    })),

    listeners(({ actions }) => ({
        saveRuleSuccess: () => {
            actions.closeModal()
            rulesLogic({ ruleType: ErrorTrackingRuleType.Severity }).actions.loadRules()
        },
        deleteRuleSuccess: () => {
            actions.closeModal()
            rulesLogic({ ruleType: ErrorTrackingRuleType.Severity }).actions.loadRules()
        },
        openModal: () => actions.resetMatchCount(),
        updateRule: () => actions.resetMatchCount(),
        increaseDateRange: () => actions.loadMatchCount(),
    })),

    selectors({
        hasFilters: [(s) => [s.rule], (rule: EditableSeverityRule): boolean => (rule.filters.values?.length ?? 0) > 0],
        hasSeverity: [(s) => [s.rule], (rule: EditableSeverityRule): boolean => rule.severity !== null],
    }),
])
