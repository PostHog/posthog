export const sentryMigrationLogic = kea<sentryMigrationLogicType>([
    path([
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingConfigurationScene',
        'sentry_migration',
        'sentryMigrationLogic',
    ]),

    connect(() => ({
        values: [teamLogic, ['currentTeamId'], featureFlagLogic, ['featureFlags']],
    })),

    actions({
        setAuthToken: (authToken: string) => ({ authToken }),
        setBaseUrl: (baseUrl: string) => ({ baseUrl }),
        selectProject: (projectKey: string | null) => ({ projectKey }),
        toggleItem: (itemId: string) => ({ itemId }),
        setSelectedItemIds: (itemIds: string[]) => ({ itemIds }),
        disconnect: true,
        selectSource: (source: ImportSource) => ({ source }),
        selectHosting: (hosting: SentryHosting) => ({ hosting }),
        confirmLocation: true,
        setStep: (step: ImportWizardStep) => ({ step }),
        goToNextStep: true,
        goToPreviousStep: true,
        resetWizard: true,
    }),

    loaders(({ values }) => ({
        // null until the user connects, so "no projects" means Sentry answered with none.
        projects: [
            null as SentryProjectApi[] | null,
            {
                loadProjects: async (_: void, breakpoint) => {
                    const authToken = values.authToken
                    const response = await errorTrackingSentryMigrationProjectsCreate(String(values.currentTeamId), {
                        auth_token: authToken,
                        base_url: values.baseUrl,
                    })
                    breakpoint()
                    // The user disconnected or changed the token while this request was in flight.
                    if (values.authToken !== authToken) {
                        return values.projects
                    }
                    return response.projects
                },
            },
        ],
        items: [
            null as SentryMigrationItemApi[] | null,
            {
                loadPreview: async (_: { keepSelection?: boolean } = {}, breakpoint) => {
                    const project = values.selectedProject
                    if (!project) {
                        return null
                    }
                    const response = await errorTrackingSentryMigrationPreviewCreate(String(values.currentTeamId), {
                        auth_token: values.authToken,
                        base_url: values.baseUrl,
                        organization_slug: project.organization_slug,
                        project_slug: project.project_slug,
                        region_url: project.region_url,
                    })
                    breakpoint()
                    // Rate limits and automatic rules are still behind flags, so don't offer to import what the user can't see.
                    const showRateLimits = !!values.featureFlags[FEATURE_FLAGS.ERROR_TRACKING_RATE_LIMITING]
                    const showBuiltInFilters = !!values.featureFlags[FEATURE_FLAGS.ERROR_TRACKING_BUILT_IN_FILTERS]
                    return response.items.filter(
                        (item) =>
                            // An inbound filter PostHog has no rule for is left out. A rate limit stays, to say why it can't come over.
                            !(item.category === 'inbound_filter' && item.fit === 'unsupported') &&
                            (showRateLimits || item.category !== 'rate_limit') &&
                            (showBuiltInFilters || !item.built_in_filter)
                    )
                },
            },
        ],
        importResult: [
            null as SentryMigrationApplyResponseApi | null,
            {
                applyImport: async () => {
                    const project = values.selectedProject
                    if (!project || values.selectedItemIds.length === 0) {
                        return null
                    }
                    return await errorTrackingSentryMigrationApplyCreate(String(values.currentTeamId), {
                        auth_token: values.authToken,
                        base_url: values.baseUrl,
                        organization_slug: project.organization_slug,
                        project_slug: project.project_slug,
                        region_url: project.region_url,
                        item_ids: values.selectedItemIds,
                    })
                },
            },
        ],
    })),

    reducers({
        step: [
            ImportWizardStep.Source as ImportWizardStep,
            {
                selectSource: () => ImportWizardStep.Location,
                selectHosting: (_, { hosting }) =>
                    hosting === 'cloud' ? ImportWizardStep.Token : ImportWizardStep.Location,
                confirmLocation: () => ImportWizardStep.Token,
                // A stale response returns the previous projects, which are null until a connection succeeds.
                loadProjectsSuccess: (state, { projects }) => (projects ? ImportWizardStep.Project : state),
                selectProject: () => ImportWizardStep.Project,
                disconnect: () => ImportWizardStep.Token,
                setStep: (_, { step }) => step,
                resetWizard: () => ImportWizardStep.Source,
            },
        ],
        source: [
            null as ImportSource | null,
            {
                selectSource: (_, { source }) => source,
                resetWizard: () => null,
            },
        ],
        hosting: [
            null as SentryHosting | null,
            {
                selectHosting: (_, { hosting }) => hosting,
                resetWizard: () => null,
            },
        ],
        // Kept in memory only, so the token is gone when the user leaves the page.
        authToken: [
            '',
            {
                setAuthToken: (_, { authToken }) => authToken,
                // A token belongs to one Sentry server, so don't send it to a server the user picks afterwards.
                selectHosting: () => '',
                setBaseUrl: () => '',
                disconnect: () => '',
                resetWizard: () => '',
            },
        ],
        baseUrl: [
            SENTRY_CLOUD_URL as string,
            {
                setBaseUrl: (_, { baseUrl }) => baseUrl,
                selectHosting: (state, { hosting }) =>
                    hosting === 'cloud' ? SENTRY_CLOUD_URL : state === SENTRY_CLOUD_URL ? '' : state,
                resetWizard: () => SENTRY_CLOUD_URL,
            },
        ],
        selectedProjectKey: [
            null as string | null,
            {
                selectProject: (_, { projectKey }) => projectKey,
                loadProjects: () => null,
                disconnect: () => null,
                resetWizard: () => null,
            },
        ],
        // Plain reducer cases, because an action listed in two loaders gets one success action shaped for the first.
        projects: {
            disconnect: () => null,
            resetWizard: () => null,
        },
        items: {
            selectProject: () => null,
            loadProjects: () => null,
            disconnect: () => null,
            resetWizard: () => null,
        },
        previewFailed: [
            false,
            {
                loadProjects: () => false,
                loadPreview: () => false,
                loadPreviewFailure: () => true,
                selectProject: () => false,
                disconnect: () => false,
                resetWizard: () => false,
            },
        ],
        selectedItemIds: [
            [] as string[],
            {
                setSelectedItemIds: (_, { itemIds }) => itemIds,
                loadPreviewSuccess: (state, { items, payload }) =>
                    payload?.keepSelection
                        ? state.filter((id) => (items ?? []).some((item) => item.id === id && isSelectable(item)))
                        : defaultSelectedItemIds(items ?? []),
                loadProjects: () => [],
                selectProject: () => [],
                disconnect: () => [],
                resetWizard: () => [],
            },
        ],
        importResult: {
            // Changing the selection starts a new import, so the last result no longer applies.
            toggleItem: () => null,
            loadProjects: () => null,
            selectProject: () => null,
            disconnect: () => null,
            resetWizard: () => null,
        },
    }),

    selectors({
        selectedProject: [
            (s) => [s.projects, s.selectedProjectKey],
            (projects: SentryProjectApi[] | null, selectedProjectKey: string | null): SentryProjectApi | null =>
                projects?.find((project: SentryProjectApi) => sentryProjectKey(project) === selectedProjectKey) ?? null,
        ],
        importPlan: [
            (s) => [s.items, s.selectedItemIds],
            (items: SentryMigrationItemApi[] | null, selectedItemIds: string[]): SentryImportPlan =>
                buildImportPlan(items ?? [], selectedItemIds),
        ],
        steps: [
            (s) => [s.items],
            (items: SentryMigrationItemApi[] | null): ImportWizardStepperStep<ImportWizardStep>[] => wizardSteps(items),
        ],
    }),

    listeners(({ actions, values }) => ({
        goToNextStep: () => {
            const index = values.steps.findIndex((step) => step.key === values.step)
            const next = values.steps[index + 1]
            if (next) {
                actions.setStep(next.key)
            }
        },
        goToPreviousStep: () => {
            const index = values.steps.findIndex((step) => step.key === values.step)
            if (index > 0) {
                actions.setStep(values.steps[index - 1].key)
            }
        },
        toggleItem: ({ itemId }) => {
            actions.setSelectedItemIds(toggleItemSelection(values.items ?? [], values.selectedItemIds, itemId))
        },
        selectProject: ({ projectKey }) => {
            if (projectKey) {
                actions.loadPreview()
            }
        },
        applyImportSuccess: ({ importResult }) => {
            if (!importResult) {
                return
            }
            lemonToast.success(importSummary(importResult))
            rulesLogic.findMounted({ ruleType: ErrorTrackingRuleType.Suppression })?.actions.loadRules()
            rateLimitConfigLogic.findMounted()?.actions.loadConfig()
            builtInFiltersLogic.findMounted()?.actions.loadBuiltInFilters()
            actions.loadPreview({ keepSelection: true })
        },
    })),
])
