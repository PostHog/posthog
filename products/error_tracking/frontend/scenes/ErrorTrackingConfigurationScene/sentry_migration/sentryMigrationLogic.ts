export type ImportSource = 'sentry'

export type SentryHosting = 'cloud' | 'self_hosted'

export function sentryProjectKey(project: SentryProjectApi): string {
    return `${project.organization_slug}/${project.project_slug}`
}

function pluralRules(count: number, kind: string): string {
    return `${count} ${kind} suppression ${count === 1 ? 'rule' : 'rules'}`
}

export function importSummary(result: SentryMigrationApplyResponseApi): string {
    const parts: string[] = []
    if (result.suppression_rules_created > 0) {
        parts.push(`created ${pluralRules(result.suppression_rules_created, 'manual')}`)
    }
    if (result.built_in_filters_enabled > 0) {
        parts.push(`turned on ${pluralRules(result.built_in_filters_enabled, 'automatic')}`)
    }
    if (result.rate_limit_updated) {
        parts.push('set the rate limit')
    }
    if (parts.length === 0) {
        return 'Everything you selected is already in PostHog.'
    }
    const sentence = parts.length === 1 ? parts[0] : `${parts.slice(0, -1).join(', ')} and ${parts[parts.length - 1]}`
    return `Imported from Sentry: ${sentence}.`
}

