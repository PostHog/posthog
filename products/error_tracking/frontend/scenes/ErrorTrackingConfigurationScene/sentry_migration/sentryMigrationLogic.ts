export const sentryMigrationLogic = kea<sentryMigrationLogicType>([
    path([
        'products',
        'error_tracking',
        'scenes',
        'ErrorTrackingConfigurationScene',
        'sentry_migration',
        'sentryMigrationLogic',
    ]),

    connect(() => ({
        values: [teamLogic, ['currentTeamId'], featureFlagLogic, ['featureFlags']],
    })),

    actions({
        setAuthToken: (authToken: string) => ({ authToken }),
        setBaseUrl: (baseUrl: string) => ({ baseUrl }),
        selectProject: (projectKey: string | null) => ({ projectKey }),
        toggleItem: (itemId: string) => ({ itemId }),
        setSelectedItemIds: (itemIds: string[]) => ({ itemIds }),
        disconnect: true,
    }),

    loaders(({ values }) => ({
        // null until the user connects, so "no projects" means Sentry answered with none.
        projects: [
            null as SentryProjectApi[] | null,
            {
                loadProjects: async (_: void, breakpoint) => {
                    const authToken = values.authToken
                    const response = await errorTrackingSentryMigrationProjectsCreate(String(values.currentTeamId), {
                        auth_token: authToken,
                        base_url: values.baseUrl,
                    })
                    breakpoint()
                    // The user disconnected or changed the token while this request was in flight.
                    if (values.authToken !== authToken) {
                        return values.projects
                    }
                    return response.projects
                },
                disconnect: () => null,
            },
        ],
        items: [
            null as SentryMigrationItemApi[] | null,
            {
                loadPreview: async (_: void, breakpoint) => {
                    const project = values.selectedProject
                    if (!project) {
                        return null
                    }
                    const response = await errorTrackingSentryMigrationPreviewCreate(String(values.currentTeamId), {
                        auth_token: values.authToken,
                        base_url: values.baseUrl,
                        organization_slug: project.organization_slug,
                        project_slug: project.project_slug,
                        region_url: project.region_url,
                    })
                    breakpoint()
                    // Rate limit settings are still behind a flag, so don't offer to import one the user can't see.
                    const showRateLimits = !!values.featureFlags[FEATURE_FLAGS.ERROR_TRACKING_RATE_LIMITING]
                    return response.items.filter((item) => showRateLimits || !item.rate_limit)
                },
                selectProject: () => null,
                disconnect: () => null,
            },
        ],
        importResult: [
            null as SentryMigrationApplyResponseApi | null,
            {
                applyImport: async () => {
                    const project = values.selectedProject
                    if (!project || values.selectedItemIds.length === 0) {
                        return null
                    }
                    return await errorTrackingSentryMigrationApplyCreate(String(values.currentTeamId), {
                        auth_token: values.authToken,
                        base_url: values.baseUrl,
                        organization_slug: project.organization_slug,
                        project_slug: project.project_slug,
                        region_url: project.region_url,
                        item_ids: values.selectedItemIds,
                    })
                },
            },
        ],
    })),

    reducers({
        // Kept in memory only, so the token is gone when the user leaves the page.
        authToken: [
            '',
            {
                setAuthToken: (_, { authToken }) => authToken,
                disconnect: () => '',
            },
        ],
        baseUrl: [
            SENTRY_CLOUD_URL as string,
            {
                setBaseUrl: (_, { baseUrl }) => baseUrl,
            },
        ],
        selectedProjectKey: [
            null as string | null,
            {
                selectProject: (_, { projectKey }) => projectKey,
                loadProjects: () => null,
                disconnect: () => null,
            },
        ],
        previewFailed: [
            false,
            {
                loadPreview: () => false,
                loadPreviewFailure: () => true,
                selectProject: () => false,
                disconnect: () => false,
            },
        ],
        selectedItemIds: [
            [] as string[],
            {
                setSelectedItemIds: (_, { itemIds }) => itemIds,
                loadPreviewSuccess: (_, { items }) => defaultSelectedItemIds(items ?? []),
                selectProject: () => [],
                disconnect: () => [],
            },
        ],
    }),

    selectors({
        selectedProject: [
            (s) => [s.projects, s.selectedProjectKey],
            (projects: SentryProjectApi[] | null, selectedProjectKey: string | null): SentryProjectApi | null =>
                projects?.find((project: SentryProjectApi) => sentryProjectKey(project) === selectedProjectKey) ?? null,
        ],
        isConnected: [(s) => [s.projects], (projects: SentryProjectApi[] | null): boolean => projects !== null],
        projectsByOrganization: [
            (s) => [s.projects],
            (projects: SentryProjectApi[] | null): SentryOrganizationProjects[] => groupByOrganization(projects ?? []),
        ],
    }),

    listeners(({ actions, values }) => ({
        toggleItem: ({ itemId }) => {
            actions.setSelectedItemIds(toggleItemSelection(values.items ?? [], values.selectedItemIds, itemId))
        },
        selectProject: ({ projectKey }) => {
            if (projectKey) {
                actions.loadPreview()
            }
        },
        applyImportSuccess: ({ importResult }) => {
            if (!importResult) {
                return
            }
            lemonToast.success(importSummary(importResult))
            rulesLogic.findMounted({ ruleType: ErrorTrackingRuleType.Suppression })?.actions.loadRules()
            rateLimitConfigLogic.findMounted()?.actions.loadConfig()
            actions.loadPreview()
        },
    })),
])
