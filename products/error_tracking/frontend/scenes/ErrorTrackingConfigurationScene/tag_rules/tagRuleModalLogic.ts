export const tagRuleModalLogic = kea<tagRuleModalLogicType>([
    path(['products', 'error_tracking', 'scenes', 'ErrorTrackingConfigurationScene', 'tag_rules', 'tagRuleModalLogic']),

    connect(() => ({
        values: [rulesLogic({ ruleType: ErrorTrackingRuleType.Tag }), ['rules']],
        actions: [
            rulesLogic({ ruleType: ErrorTrackingRuleType.Tag }),
            ['loadRules', 'deleteSelectedRulesSuccess', 'finishReorderingRulesSuccess'],
        ],
    })),

    actions({
        openModal: (rule?: ErrorTrackingTagRule) => ({ rule: rule ?? null }),
        closeModal: true,
        updateRule: (rule: EditableTagRule) => ({ rule }),
        updateLabel: (label: string) => ({ label }),
        updateDescription: (description: string) => ({ description }),
        increaseDateRange: true,
        saveRule: true,
    }),

    reducers({
        isOpen: [false, { openModal: () => true, closeModal: () => false }],
        rule: [
            emptyRule() as EditableTagRule,
            {
                openModal: (_: EditableTagRule, { rule }: { rule: ErrorTrackingTagRule | null }) => rule ?? emptyRule(),
                updateRule: (_: EditableTagRule, { rule }: { rule: EditableTagRule }) => rule,
                updateLabel: (state: EditableTagRule, { label }: { label: string }) => ({ ...state, label }),
                updateDescription: (state: EditableTagRule, { description }: { description: string }) => ({
                    ...state,
                    description,
                }),
            },
        ],
        savedFilters: [
            null as UniversalFiltersGroup | null,
            {
                openModal: (_: UniversalFiltersGroup | null, { rule }: { rule: ErrorTrackingTagRule | null }) =>
                    rule?.filters ?? null,
            },
        ],
        dateRange: [
            '-7d' as string,
            {
                openModal: () => '-7d',
                updateRule: () => '-7d',
                increaseDateRange: (state: string) => ({ '-7d': '-30d', '-30d': '-90d' })[state] ?? state,
            },
        ],
    }),

    loaders(({ values }) => ({
        matchResult: [
            null as { exceptionCount: number; issueCount: number } | null,
            {
                loadMatchCount: async () => {
                    const filters = values.rule.filters as UniversalFiltersGroup
                    const properties = (filters.values as AnyPropertyFilter[]) ?? []
                    if (properties.length === 0) {
                        return null
                    }
                    const response = (await api.query({
                        kind: NodeKind.EventsQuery,
                        event: '$exception',
                        select: ['count()', 'count(distinct issue_id)'],
                        after: values.dateRange,
                        tags: { productKey: ProductKey.ERROR_TRACKING },
                        fixedProperties: [{ type: filters.type ?? FilterLogicalOperator.And, values: properties }],
                        where: [firstExceptionOfNewIssue(values.dateRange)],
                    })) as Record<string, any>
                    return {
                        exceptionCount: response.results?.[0]?.[0] ?? 0,
                        issueCount: response.results?.[0]?.[1] ?? 0,
                    }
                },
                resetMatchCount: () => null,
            },
        ],
        saving: [
            false,
            {
                persistRule: async () => {
                    const { id, label, description, filters } = values.rule
                    const projectId = String(teamLogic.values.currentTeamId)
                    const body = { label, description, filters: filters as ErrorTrackingIssueTagRuleFiltersApi }
                    if (id === 'new') {
                        const order_key = Math.max(-1, ...values.rules.map((rule) => rule.order_key)) + 1
                        await errorTrackingTagRulesCreate(projectId, { ...body, order_key })
                    } else {
                        await errorTrackingTagRulesUpdate(projectId, id, body)
                    }
                    return true
                },
            },
        ],
        deleting: [
            false,
            {
                deleteRule: async () => {
                    await destroyTagRule(values.rule.id)
                    return true
                },
            },
        ],
    })),

    listeners(({ actions, values }) => ({
        saveRule: () => {
            if (!values.removesExistingTags) {
                actions.persistRule()
                return
            }
            LemonDialog.open({
                title: 'Remove this tag from existing issues?',
                description:
                    'The filters now read different event properties, so saving removes this tag from every issue that has it. New issues get the tag when their first exception matches the new filters. Other issues get it back in the next daily check if they had a matching exception in the past day. Filters on the exception list check only the first exception.',
                primaryButton: { children: 'Save', status: 'danger', onClick: () => actions.persistRule() },
                secondaryButton: { children: 'Cancel' },
            })
        },
        persistRuleSuccess: () => {
            actions.closeModal()
            actions.loadRules()
            reloadIssueTagDefinitions()
        },
        deleteRuleSuccess: () => {
            actions.closeModal()
            actions.loadRules()
            reloadIssueTagDefinitions()
        },
        deleteSelectedRulesSuccess: reloadIssueTagDefinitions,
        finishReorderingRulesSuccess: reloadIssueTagDefinitions,
        openModal: () => actions.resetMatchCount(),
        updateRule: () => actions.resetMatchCount(),
        increaseDateRange: () => actions.loadMatchCount(),
    })),

    selectors({
        hasFilters: [(s) => [s.rule], (rule: EditableTagRule): boolean => (rule.filters.values?.length ?? 0) > 0],
        hasLabel: [(s) => [s.rule], (rule: EditableTagRule): boolean => rule.label.trim().length > 0],
        removesExistingTags: [
            (s) => [s.savedFilters, s.rule],
            (savedFilters: UniversalFiltersGroup | null, rule: EditableTagRule): boolean => {
                if (savedFilters === null) {
                    return false
                }
                const before = new Set(readProperties(savedFilters))
                const after = new Set(readProperties(rule.filters))
                return before.size !== after.size || [...after].some((key) => !before.has(key))
            },
        ],
    }),
])
