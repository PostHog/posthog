type EditableTagRule = ErrorTrackingTagRule | ErrorTrackingTagRuleNew

function emptyRule(): ErrorTrackingTagRuleNew {
    return {
        id: 'new',
        label: '',
        description: '',
        filters: { type: FilterLogicalOperator.And, values: [] },
        disabled_data: null,
        order_key: 0,
    }
}

// An open issue list loads its label definitions only once. Reloading them after a rule change makes the list drop a
// filter on a deleted rule's label, which the query would otherwise ignore.
function reloadIssueTagDefinitions(): void {
    issueTagDefinitionsLogic.findMounted()?.actions.loadIssueTagDefinitions()
}

