export interface BreakdownSinglePropertyStat {
    label: string
    count: number
}

function getBreakdownPropertyTitle(property: string): string {
    return getCoreFilterDefinition(property, TaxonomicFilterGroupType.EventProperties)?.label ?? property
}

export function getSelectedEventBreakdownProperties(
    properties: ErrorEventProperties | null,
    isCloudOrDev: boolean | undefined
): BreakdownPreset[] {
    if (!properties) {
        return []
    }

    return Object.entries(getAdditionalProperties(properties, isCloudOrDev))
        .filter(([, value]) => value === null || ['string', 'number', 'boolean'].includes(typeof value))
        .map(([property]) => ({ property, title: getBreakdownPropertyTitle(property) }))
        .sort((left, right) => left.title.localeCompare(right.title, undefined, { sensitivity: 'base' }))
        .slice(0, MAX_SELECTED_EVENT_BREAKDOWN_PROPERTIES)
}

export function getBreakdownForPropertyFromResponse(
    response: ErrorTrackingBreakdownsQueryResponse | null,
    property: string
): { properties: BreakdownSinglePropertyStat[]; totalCount: number } {
    const properties: BreakdownSinglePropertyStat[] = []
    let totalCount = 0
    const propertyData = response?.results?.[property]

    if (propertyData) {
        propertyData.values.forEach((value) => {
            properties.push({
                label: value.value,
                count: value.count,
            })
        })

        totalCount = propertyData.total_count || 0

        const displayedCount = propertyData.values.reduce((sum, value) => sum + value.count, 0)
        const otherCount = Math.max(0, totalCount - displayedCount)
        if (otherCount > 0) {
            properties.push({
                label: BREAKDOWN_OTHER_DISPLAY,
                count: otherCount,
            })
        }
    }

    return { properties, totalCount }
}

export function buildBreakdownProperties(selectedEventBreakdownProperties: BreakdownPreset[]): BreakdownPreset[] {
    const presetPropertyNames = new Set(BREAKDOWN_PRESETS.map(({ property }) => property))
    return [
        ...BREAKDOWN_PRESETS,
        ...selectedEventBreakdownProperties.filter(({ property }) => !presetPropertyNames.has(property)),
    ]
}

