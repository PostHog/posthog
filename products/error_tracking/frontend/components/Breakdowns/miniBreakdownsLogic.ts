export const miniBreakdownsLogic = kea<miniBreakdownsLogicType>([
    path(['products', 'error_tracking', 'components', 'Breakdowns', 'miniBreakdownsLogic']),
    props({} as MiniBreakdownsLogicProps),
    key(({ issueId }: MiniBreakdownsLogicProps) => issueId),
    connect((props: MiniBreakdownsLogicProps) => ({
        values: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['dateRange', 'filterGroup', 'filterTestAccounts'],
            errorTrackingIssueSceneLogic({ id: props.issueId }),
            ['selectedEvent'],
            preflightLogic,
            ['isCloudOrDev'],
        ],
    })),
    actions({
        closeBreakdownDetails: true,
        loadResponse: true,
        openBreakdownDetails: (breakdown: BreakdownPreset) => ({ breakdown }),
    }),
    reducers({
        selectedBreakdownProperty: [
            null as BreakdownPreset | null,
            {
                openBreakdownDetails: (_, { breakdown }) => breakdown,
                closeBreakdownDetails: () => null,
            },
        ],
        breakdownDetailsError: [
            null as string | null,
            {
                loadBreakdownDetails: () => null,
                loadBreakdownDetailsSuccess: () => null,
                loadBreakdownDetailsFailure: (_, { error }) => error,
                closeBreakdownDetails: () => null,
            },
        ],
        responseError: [
            null as string | null,
            {
                loadResponse: () => null,
                loadResponseSuccess: () => null,
                loadResponseFailure: (_, { error }) => error,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        breakdownDetails: [
            null as ErrorTrackingBreakdownsQueryResponse | null,
            {
                loadBreakdownDetails: async ({ property }: { property: string }, breakpoint) => {
                    const result = await api.query(
                        errorTrackingBreakdownsQuery({
                            issueId: props.issueId,
                            dateRange: values.dateRange,
                            filterGroup: values.filterGroup,
                            filterTestAccounts: values.filterTestAccounts,
                            breakdownProperties: [property],
                            maxValuesPerProperty: BREAKDOWN_DETAILS_LIMIT,
                        }),
                        { refresh: 'blocking' }
                    )
                    breakpoint()
                    return result
                },
            },
        ],
        response: [
            null as ErrorTrackingBreakdownsQueryResponse | null,
            {
                loadResponse: async (_: { value: true }, breakpoint) => {
                    await breakpoint(100)
                    const startTime = Date.now()
                    // Read connected values before the request because either connected logic may unmount while it runs.
                    const { dateRange, filterGroup, filterTestAccounts } = values
                    const breakdownProperties = values.breakdownProperties.map((preset) => preset.property)
                    const result = await api.query(
                        errorTrackingBreakdownsQuery({
                            issueId: props.issueId,
                            dateRange,
                            filterGroup,
                            filterTestAccounts,
                            breakdownProperties,
                            maxValuesPerProperty: LIMIT_ITEMS,
                        }),
                        { refresh: 'blocking' }
                    )
                    breakpoint()

                    posthog.capture(BreakdownsEvents.MiniBreakdownsLoaded, {
                        issueId: props.issueId,
                        dateRange,
                        filterTestAccounts,
                        breakdownProperties,
                        duration: Date.now() - startTime,
                        cached: (result as CachedErrorTrackingBreakdownsQueryResponse).is_cached ?? false,
                    })

                    return result
                },
            },
        ],
    })),
    selectors(() => ({
        selectedEventBreakdownProperties: [
            (selectors) => [selectors.selectedEvent, selectors.isCloudOrDev],
            (selectedEvent: ErrorEventType | null, isCloudOrDev: boolean | undefined): BreakdownPreset[] =>
                getSelectedEventBreakdownProperties(selectedEvent?.properties ?? null, isCloudOrDev),
        ],
        breakdownProperties: [
            (selectors) => [selectors.selectedEventBreakdownProperties],
            (selectedEventBreakdownProperties: BreakdownPreset[]) =>
                buildBreakdownProperties(selectedEventBreakdownProperties),
        ],
        visibleBreakdownProperties: [
            (selectors) => [
                selectors.breakdownProperties,
                selectors.response,
                selectors.responseLoading,
                selectors.responseError,
            ],
            (
                breakdownProperties: BreakdownPreset[],
                response: ErrorTrackingBreakdownsQueryResponse | null,
                responseLoading: boolean,
                responseError: string | null
            ): BreakdownPreset[] => {
                if (!response || responseLoading || responseError) {
                    return breakdownProperties
                }

                return breakdownProperties.filter(({ property }) => {
                    const { properties } = getBreakdownForPropertyFromResponse(response, property)
                    return !(
                        properties.length === 0 ||
                        (properties.length === 1 && properties[0].label === BREAKDOWN_NULL_STRING_LABEL)
                    )
                })
            },
        ],
        getBreakdownForProperty: [
            (selectors) => [selectors.response],
            (response: ErrorTrackingBreakdownsQueryResponse | null) =>
                (property: string): { properties: BreakdownSinglePropertyStat[]; totalCount: number } =>
                    getBreakdownForPropertyFromResponse(response, property),
        ],
    })),
    subscriptions(({ actions }) => ({
        dateRange: (value, oldValue) => {
            if (oldValue !== undefined && value !== oldValue) {
                actions.loadResponse()
            }
        },
        filterTestAccounts: (value, oldValue) => {
            if (oldValue !== undefined && value !== oldValue) {
                actions.loadResponse()
            }
        },
        filterGroup: (value, oldValue) => {
            if (oldValue !== undefined && value !== oldValue) {
                actions.loadResponse()
            }
        },
        selectedEventBreakdownProperties: (value: BreakdownPreset[], oldValue: BreakdownPreset[] | undefined) => {
            const propertyNames = value.map(({ property }) => property).join('\0')
            const previousPropertyNames = oldValue?.map(({ property }) => property).join('\0')
            if (oldValue !== undefined && propertyNames !== previousPropertyNames) {
                actions.loadResponse()
            }
        },
    })),
    listeners(({ actions }) => ({
        openBreakdownDetails: ({ breakdown }) => actions.loadBreakdownDetails({ property: breakdown.property }),
    })),
    events(({ actions }) => ({
        afterMount: () => {
            actions.loadResponse()
        },
    })),
])
