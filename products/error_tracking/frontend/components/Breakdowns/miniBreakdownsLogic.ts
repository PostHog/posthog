export const miniBreakdownsLogic = kea<miniBreakdownsLogicType>([
    path(['products', 'error_tracking', 'components', 'Breakdowns', 'miniBreakdownsLogic']),
    props({} as MiniBreakdownsLogicProps),
    key(({ issueId }: MiniBreakdownsLogicProps) => issueId),
    connect(() => ({
        values: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['dateRange', 'filterTestAccounts'],
        ],
        actions: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['setDateRange', 'setFilterTestAccounts'],
        ],
    })),
    actions({
        addBreakdownProperty: (property: string) => ({ property }),
        removeBreakdownProperty: (property: string) => ({ property }),
        openPropertyPicker: true,
    }),
    reducers({
        customBreakdownProperties: [
            [] as string[],
            {
                addBreakdownProperty: (properties, { property }) =>
                    BREAKDOWN_PRESETS.some((preset) => preset.property === property) || properties.includes(property)
                        ? properties
                        : [...properties, property],
                removeBreakdownProperty: (properties, { property }) =>
                    properties.filter((candidate) => candidate !== property),
            },
        ],
        propertyPickerOpenRequest: [
            0,
            {
                openPropertyPicker: (request) => request + 1,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        response: [
            null as ErrorTrackingBreakdownsQueryResponse | null,
            {
                loadResponse: async () => {
                    const startTime = Date.now()
                    // Read connected values up front: the logic (and its connected issueFiltersLogic)
                    // may unmount while the query is in flight, and accessing values afterwards would throw.
                    const { dateRange, filterTestAccounts } = values
                    const breakdownProperties = values.breakdownProperties.map((preset) => preset.property)
                    const result = await api.query(
                        errorTrackingBreakdownsQuery({
                            issueId: props.issueId,
                            dateRange,
                            filterTestAccounts,
                            breakdownProperties,
                            maxValuesPerProperty: LIMIT_ITEMS,
                        }),
                        { refresh: 'blocking' }
                    )

                    posthog.capture(BreakdownsEvents.MiniBreakdownsLoaded, {
                        issueId: props.issueId,
                        dateRange,
                        filterTestAccounts,
                        breakdownProperties,
                        duration: Date.now() - startTime,
                        cached: (result as CachedErrorTrackingBreakdownsQueryResponse).is_cached ?? false,
                    })

                    return result
                },
            },
        ],
    })),
    selectors(() => ({
        breakdownProperties: [
            (s) => [s.customBreakdownProperties],
            (customBreakdownProperties: string[]): BreakdownPreset[] => [
                ...BREAKDOWN_PRESETS,
                ...customBreakdownProperties.map((property) => ({
                    property,
                    title:
                        getCoreFilterDefinition(property, TaxonomicFilterGroupType.EventProperties)?.label ?? property,
                    removable: true,
                })),
            ],
        ],
        getBreakdownForProperty: [
            (s) => [s.response],
            (response: ErrorTrackingBreakdownsQueryResponse) => {
                return (property: string): { properties: BreakdownSinglePropertyStat[]; totalCount: number } => {
                    const properties: BreakdownSinglePropertyStat[] = []
                    let totalCount = 0

                    if (response && response.results) {
                        if (property && response.results[property]) {
                            const propertyData = response.results[property]

                            propertyData.values.forEach((value: any) => {
                                properties.push({
                                    label: value.value,
                                    count: value.count,
                                })
                            })

                            totalCount = propertyData.total_count || 0

                            const displayedCount = propertyData.values.reduce((sum, value) => sum + value.count, 0)
                            const otherCount = Math.max(0, totalCount - displayedCount)
                            if (otherCount > 0) {
                                properties.push({
                                    label: BREAKDOWN_OTHER_DISPLAY,
                                    count: otherCount,
                                })
                            }
                        }
                    }

                    return { properties, totalCount }
                }
            },
        ],
    })),

    listeners(({ actions }) => ({
        addBreakdownProperty: () => actions.loadResponse(),
        removeBreakdownProperty: () => actions.loadResponse(),
        setDateRange: () => actions.loadResponse(),
        setFilterTestAccounts: () => actions.loadResponse(),
    })),

    events(({ actions }) => ({
        afterMount: () => {
            actions.loadResponse()
        },
    })),
])
