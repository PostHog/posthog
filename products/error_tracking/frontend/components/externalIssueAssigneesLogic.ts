import { LogicWrapper, MakeLogicType, afterMount, kea, key, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import {
    integrationsGithubAssigneesRetrieve,
    integrationsGitlabMembersRetrieve,
    integrationsJiraAssignableUsersRetrieve,
    integrationsLinearTeamMembersRetrieve,
} from 'products/integrations/frontend/generated/api'
import type { IntegrationAssigneeApi } from 'products/integrations/frontend/generated/api.schemas'

export type ExternalIssueAssigneeKind = 'linear' | 'github' | 'gitlab' | 'jira'

export interface ExternalIssueAssigneesLogicProps {
    integrationId: number
    kind: ExternalIssueAssigneeKind
    /** The Linear team, GitHub repository, or Jira project the issue is created in. GitLab needs none. */
    scope: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface externalIssueAssigneesLogicValues {
    users: IntegrationAssigneeApi[] | null
    usersLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface externalIssueAssigneesLogicActions {
    loadUsers: () => any
    loadUsersFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadUsersSuccess: (
        users: IntegrationAssigneeApi[],
        payload?: any
    ) => {
        users: IntegrationAssigneeApi[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface externalIssueAssigneesLogicMeta {
    key: string
}

export type externalIssueAssigneesLogicType = MakeLogicType<
    externalIssueAssigneesLogicValues,
    externalIssueAssigneesLogicActions,
    ExternalIssueAssigneesLogicProps,
    externalIssueAssigneesLogicMeta
>

async function fetchAssignees({
    integrationId,
    kind,
    scope,
}: ExternalIssueAssigneesLogicProps): Promise<IntegrationAssigneeApi[]> {
    const projectId = String(teamLogic.values.currentTeamId)
    switch (kind) {
        case 'gitlab':
            return (await integrationsGitlabMembersRetrieve(projectId, integrationId)).users
        case 'linear':
            return scope
                ? (await integrationsLinearTeamMembersRetrieve(projectId, integrationId, { team_id: scope })).users
                : []
        case 'github':
            return scope
                ? (await integrationsGithubAssigneesRetrieve(projectId, integrationId, { repository: scope })).users
                : []
        case 'jira':
            return scope
                ? (await integrationsJiraAssignableUsersRetrieve(projectId, integrationId, { project_key: scope }))
                      .users
                : []
    }
}

export const externalIssueAssigneesLogic: LogicWrapper<externalIssueAssigneesLogicType> =
    kea<externalIssueAssigneesLogicType>([
        props({} as ExternalIssueAssigneesLogicProps),
        key((props) => `${props.integrationId}:${props.scope ?? ''}`),
        path((key) => ['products', 'error_tracking', 'components', 'externalIssueAssigneesLogic', key]),
        loaders(({ props }) => ({
            users: [
                null as IntegrationAssigneeApi[] | null,
                {
                    loadUsers: async () => await fetchAssignees(props),
                },
            ],
        })),
        afterMount(({ actions }) => {
            actions.loadUsers()
        }),
    ])
