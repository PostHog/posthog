export const suppressSimilarIssuesLogic = kea<suppressSimilarIssuesLogicType>([
    path(['products', 'error_tracking', 'components', 'SuppressSimilarIssues', 'suppressSimilarIssuesLogic']),

    connect(() => ({
        actions: [issueActionsLogic, ['updateIssueStatus', 'suppressIssues']],
    })),

    actions({
        openSuggestion: (snapshots: SuppressedIssueSnapshot[]) => ({
            snapshots,
            scope: recommendedScope(buildScopeOptions(snapshots)),
        }),
        selectScope: (scope: SuppressScopeKey) => ({ scope }),
        dismissSuggestion: true,
        closeSuggestion: true,
    }),

    reducers({
        isOpen: [false, { openSuggestion: () => true, closeSuggestion: () => false }],
        // Kept after close so the dialog does not go blank while it animates out.
        snapshots: [[] as SuppressedIssueSnapshot[], { openSuggestion: (_, { snapshots }) => snapshots }],
        selectedScope: [
            null as SuppressScopeKey | null,
            {
                openSuggestion: (_, { scope }) => scope,
                selectScope: (_, { scope }) => scope,
            },
        ],
    }),

    // Before selectors, because selectedImpact reads scopeImpacts.
    loaders(({ values }) => ({
        scopeImpacts: [
            null as ScopeImpacts | null,
            {
                loadScopeImpacts: async (_, breakpoint) => {
                    await breakpoint(100)
                    const available = values.scopeOptions.filter((option) => !option.unavailableReason)
                    const impacts = await Promise.all(
                        available.map(async (option) => [option.key, await loadImpact(option.filters)] as const)
                    )
                    breakpoint()
                    return Object.fromEntries(impacts)
                },
            },
        ],
        createdRule: [
            null as ErrorTrackingSuppressionRuleApi | null,
            {
                createRule: async () => {
                    if (!values.selectedOption) {
                        return null
                    }
                    return await errorTrackingSuppressionRulesCreate(String(teamLogic.values.currentProjectId), {
                        filters: values.selectedOption.filters,
                        sampling_rate: 1,
                    })
                },
            },
        ],
    })),

    selectors({
        scopeOptions: [(s) => [s.snapshots], (snapshots: SuppressedIssueSnapshot[]) => buildScopeOptions(snapshots)],
        selectedOption: [
            (s) => [s.scopeOptions, s.selectedScope],
            (scopeOptions: SuppressScopeOption[], selectedScope: SuppressScopeKey | null): SuppressScopeOption | null =>
                scopeOptions.find((option) => option.key === selectedScope && !option.unavailableReason) ?? null,
        ],
        selectedImpact: [
            (s) => [s.scopeImpacts, s.selectedScope],
            (scopeImpacts: ScopeImpacts | null, selectedScope: SuppressScopeKey | null): ScopeImpact | null =>
                selectedScope ? (scopeImpacts?.[selectedScope] ?? null) : null,
        ],
    }),

    listeners(({ actions, values }) => {
        const offerSuggestion = (ids: string[]): void => {
            const snapshots = findIssueSnapshots(ids)
            if (recommendedScope(buildScopeOptions(snapshots))) {
                actions.openSuggestion(snapshots)
            }
        }

        return {
            updateIssueStatus: ({ id, status }) => {
                if (status === 'suppressed') {
                    offerSuggestion([id])
                }
            },
            suppressIssues: ({ ids }) => offerSuggestion(ids),
            openSuggestion: ({ snapshots, scope }) => {
                posthog.capture('error_tracking_suppress_similar_shown', {
                    issue_count: snapshots.length,
                    recommended_scope: scope,
                })
                actions.loadScopeImpacts()
            },
            dismissSuggestion: () => {
                posthog.capture('error_tracking_suppress_similar_dismissed', {
                    issue_count: values.snapshots.length,
                })
                actions.closeSuggestion()
            },
            createRuleSuccess: ({ createdRule }) => {
                if (!createdRule) {
                    return
                }
                posthog.capture('error_tracking_suppress_similar_rule_created', {
                    issue_count: values.snapshots.length,
                    scope: values.selectedScope,
                    matched_exceptions: values.selectedImpact?.exceptions ?? null,
                    matched_issues: values.selectedImpact?.issueCount ?? null,
                })
                actions.closeSuggestion()
                lemonToast.success('Suppression rule created', {
                    button: { label: 'View rules', action: () => router.actions.push(SUPPRESSION_RULES_URL) },
                })
            },
        }
    }),
])
