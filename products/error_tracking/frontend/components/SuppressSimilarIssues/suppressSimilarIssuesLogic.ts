export const suppressSimilarIssuesLogic = kea<suppressSimilarIssuesLogicType>([
    path(['products', 'error_tracking', 'components', 'SuppressSimilarIssues', 'suppressSimilarIssuesLogic']),

    connect(() => ({
        actions: [issueActionsLogic, ['updateIssueStatus', 'suppressIssues', 'mutationSuccess', 'mutationFailure']],
    })),

    actions({
        openSuggestion: (snapshots: SuppressedIssueSnapshot[]) => ({
            snapshots,
            scope: recommendedScope(buildScopeOptions(snapshots)),
        }),
        selectScope: (scope: SuppressScopeKey) => ({ scope }),
        dismissSuggestion: true,
        closeSuggestion: true,
    }),

    reducers({
        isOpen: [false, { openSuggestion: () => true, closeSuggestion: () => false }],
        // Kept after close so the dialog does not go blank while it animates out.
        snapshots: [[] as SuppressedIssueSnapshot[], { openSuggestion: (_, { snapshots }) => snapshots }],
        selectedScope: [
            null as SuppressScopeKey | null,
            {
                openSuggestion: (_, { scope }) => scope,
                selectScope: (_, { scope }) => scope,
            },
        ],
    }),

    // Before selectors, because selectedImpact reads scopeImpacts.
    loaders(({ values, cache }) => ({
        scopeImpacts: [
            null as ScopeImpacts | null,
            {
                resetScopeImpacts: () => null,
                loadScopeImpacts: async (_: void, breakpoint): Promise<ScopeImpacts> => {
                    await breakpoint(100)
                    const available = values.scopeOptions.filter((option) => !option.unavailableReason)
                    const impacts = await Promise.all(
                        available.map(async (option) => [option.key, await loadImpact(combinedFilter(option))] as const)
                    )
                    breakpoint()
                    return Object.fromEntries(impacts)
                },
            },
        ],
        createdRules: [
            null as ErrorTrackingSuppressionRuleApi[] | null,
            {
                createRules: async () => {
                    if (!values.selectedOption) {
                        return null
                    }
                    // The rules route reads this ID as the environment, as the rest of the rules UI does.
                    const teamId = String(teamLogic.values.currentTeamIdStrict)
                    // When a request fails part way, a retry must not create the earlier rules a second time.
                    const created: Map<string, ErrorTrackingSuppressionRuleApi> = (cache.createdRules ??= new Map())
                    for (const filters of values.selectedOption.rules) {
                        const key = JSON.stringify(filters)
                        if (!created.has(key)) {
                            created.set(
                                key,
                                await errorTrackingSuppressionRulesCreate(teamId, { filters, sampling_rate: 1 })
                            )
                        }
                    }
                    return values.selectedOption.rules.map((filters) => created.get(JSON.stringify(filters))!)
                },
            },
        ],
    })),

    selectors({
        scopeOptions: [(s) => [s.snapshots], (snapshots: SuppressedIssueSnapshot[]) => buildScopeOptions(snapshots)],
        selectedOption: [
            (s) => [s.scopeOptions, s.selectedScope],
            (scopeOptions: SuppressScopeOption[], selectedScope: SuppressScopeKey | null): SuppressScopeOption | null =>
                scopeOptions.find((option) => option.key === selectedScope && !option.unavailableReason) ?? null,
        ],
        selectedImpact: [
            (s) => [s.scopeImpacts, s.selectedScope],
            (scopeImpacts: ScopeImpacts | null, selectedScope: SuppressScopeKey | null): ScopeImpact | null =>
                selectedScope ? (scopeImpacts?.[selectedScope] ?? null) : null,
        ],
    }),

    listeners(({ actions, values, cache }) => {
        // The dialog opens only after the suppression request succeeds, so it never offers a rule for a failed one.
        const matchesPending = (mutationName: string, issueId: string | undefined): boolean => {
            const pending: PendingSuppression | undefined = cache.pendingSuppression
            return (
                !!pending &&
                pending.mutationName === mutationName &&
                (mutationName !== 'updateIssueStatus' || pending.ids[0] === issueId)
            )
        }

        return {
            updateIssueStatus: ({ id, status }) => {
                if (status === 'suppressed') {
                    cache.pendingSuppression = { mutationName: 'updateIssueStatus', ids: [id] }
                }
            },
            suppressIssues: ({ ids }) => {
                cache.pendingSuppression = { mutationName: 'suppressIssues', ids }
            },
            mutationFailure: ({ mutationName, issueId }) => {
                if (matchesPending(mutationName, issueId)) {
                    cache.pendingSuppression = undefined
                }
            },
            mutationSuccess: async ({ mutationName, issueId }, breakpoint) => {
                if (!matchesPending(mutationName, issueId)) {
                    return
                }
                const { ids } = cache.pendingSuppression as PendingSuppression
                cache.pendingSuppression = undefined
                let snapshots: SuppressedIssueSnapshot[]
                try {
                    snapshots = await loadIssueSnapshots(ids)
                } catch (error) {
                    posthog.captureException(error)
                    return
                }
                breakpoint()
                if (recommendedScope(buildScopeOptions(snapshots))) {
                    actions.openSuggestion(snapshots)
                }
            },
            openSuggestion: ({ snapshots, scope }) => {
                cache.createdRules = undefined
                posthog.capture('error_tracking_suppress_similar_shown', {
                    issue_count: snapshots.length,
                    recommended_scope: scope,
                })
                actions.resetScopeImpacts()
                actions.loadScopeImpacts()
            },
            dismissSuggestion: () => {
                posthog.capture('error_tracking_suppress_similar_dismissed', {
                    issue_count: values.snapshots.length,
                })
                actions.closeSuggestion()
            },
            createRulesSuccess: ({ createdRules }) => {
                if (!createdRules) {
                    return
                }
                posthog.capture('error_tracking_suppress_similar_rule_created', {
                    issue_count: values.snapshots.length,
                    rule_count: createdRules.length,
                    scope: values.selectedScope,
                    matched_exceptions: values.selectedImpact?.exceptions ?? null,
                    matched_issues: values.selectedImpact?.issueCount ?? null,
                })
                actions.closeSuggestion()
                lemonToast.success(
                    createdRules.length === 1
                        ? 'Suppression rule created'
                        : `${pluralize(createdRules.length, 'suppression rule')} created`,
                    { button: { label: 'View rules', action: () => router.actions.push(SUPPRESSION_RULES_URL) } }
                )
            },
        }
    }),
])
