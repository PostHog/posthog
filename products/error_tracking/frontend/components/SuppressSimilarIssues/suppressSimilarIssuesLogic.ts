const SUPPRESSION_RULES_URL = `${urls.errorTrackingConfiguration()}#selectedSetting=error-tracking-suppression-rules`

/** Reads what the open issue page or the issue list already knows about each issue, so no extra request is needed. */
function findIssueSnapshots(ids: string[]): SuppressedIssueSnapshot[] {
    const listResults = issuesDataNodeLogic.findMounted()?.values.results ?? []
    return ids.flatMap((id) => {
        const sceneLogic = errorTrackingIssueSceneLogic.findMounted({ id })
        const sceneIssue = sceneLogic?.values.issue
        if (sceneLogic && sceneIssue) {
            const event = sceneLogic.values.selectedEvent ?? sceneLogic.values.initialEvent
            return [snapshotFromIssueEvent(sceneIssue, event?.properties)]
        }
        const listIssue = listResults.find((issue) => issue.id === id)
        return listIssue ? [snapshotFromListIssue(listIssue)] : []
    })
}

async function loadImpact(filters: SuppressionFilterGroup): Promise<ScopeImpact> {
    const query: EventsQuery = {
        kind: NodeKind.EventsQuery,
        event: '$exception',
        select: ['count()', 'count(distinct issue_id)'],
        after: '-7d',
        fixedProperties: [filters],
        tags: { productKey: ProductKey.ERROR_TRACKING },
    }
    const response = await api.query(query)
    const [exceptions = 0, issueCount = 0] = response.results?.[0] ?? []
    return { exceptions, issueCount }
}

