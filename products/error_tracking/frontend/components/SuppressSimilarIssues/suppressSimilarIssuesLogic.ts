const SUPPRESSION_RULES_URL = `${urls.errorTrackingConfiguration()}#selectedSetting=error-tracking-suppression-rules`

// A person can rename an issue or edit its description, so those labels can stop matching
// the exceptions a rule must catch. The latest event carries the real type and message.
async function loadIssueSnapshots(ids: string[]): Promise<SuppressedIssueSnapshot[]> {
    const response = await api.queryHogQL<[string, unknown, unknown][]>(
        hogql`SELECT issue_id, argMax(properties.$exception_types, timestamp), argMax(properties.$exception_values, timestamp)
            FROM events
            WHERE event = '$exception' AND timestamp > now() - INTERVAL 30 DAY AND has(${ids}, toString(issue_id))
            GROUP BY issue_id`,
        { productKey: ProductKey.ERROR_TRACKING }
    )
    return response.results.map(snapshotFromLatestEvent)
}

async function loadImpact(filter: PropertyGroupFilterValue): Promise<ScopeImpact> {
    const query: EventsQuery = {
        kind: NodeKind.EventsQuery,
        event: '$exception',
        select: ['count()', 'count(distinct issue_id)'],
        after: '-7d',
        fixedProperties: [filter],
        tags: { productKey: ProductKey.ERROR_TRACKING },
    }
    const response = await api.query(query)
    const [exceptions = 0, issueCount = 0] = response.results?.[0] ?? []
    return { exceptions, issueCount }
}

