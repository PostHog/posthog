export type sessionTabLogicType = MakeLogicType<
    sessionTabLogicValues,
    sessionTabLogicActions,
    SessionTabLogicProps,
    sessionTabLogicMeta
>

export const sessionTabLogic = kea<sessionTabLogicType>([
    path((key) => ['scenes', 'error-tracking', 'exceptionCard', 'sessionTab', key]),
    props({} as SessionTabLogicProps),
    key(({ sessionId }) => sessionId as KeyType),
    connect(({ sessionId }: SessionTabLogicProps) => ({
        values: [
            sessionRecordingDataCoordinatorLogic(getRecordingProps(sessionId)),
            ['isNotFound', 'sessionPlayerMetaDataLoading', 'sessionPlayerData'],
        ],
        actions: [
            sessionRecordingDataCoordinatorLogic(getRecordingProps(sessionId)),
            ['loadRecordingMetaSuccess'],
            sessionRecordingPlayerLogic(getRecordingProps(sessionId)),
            ['seekToTimestamp', 'setPlay', 'setPause'],
        ],
    })),

    propsChanged(({ actions, props }, oldProps) => {
        if (props.timestamp && props.timestamp !== oldProps.timestamp) {
            actions.setRecordingTimestamp(dayjs(props.timestamp), 5000)
        }
    }),

    actions({
        setRecordingTimestamp: (timestamp: Dayjs, offset: number) => ({ timestamp, offset }),
    }),

    defaults({
        recordingTimestamp: null as number | null,
        exceptionTimestamp: null as number | null,
    }),

    reducers({
        recordingTimestamp: {
            setRecordingTimestamp: (_, { timestamp, offset }: { timestamp: Dayjs; offset: number }) =>
                dayjs(timestamp).valueOf() - offset,
        },
        exceptionTimestamp: {
            setRecordingTimestamp: (_, { timestamp }: { timestamp: Dayjs }) => dayjs(timestamp).valueOf(),
        },
    }),
    selectors({
        sessionId: [(_, p) => [p.sessionId], (sessionId: string) => sessionId],
        recordingProps: [
            (_, p) => [p.sessionId],
            (sessionId: string) => {
                return getRecordingProps(sessionId)
            },
        ],
        recordingBounds: [
            (s) => [s.sessionPlayerData, s.sessionPlayerMetaDataLoading],
            (sessionPlayerData: SessionPlayerData, sessionPlayerMetaDataLoading: boolean): RecordingBounds | null => {
                if (sessionPlayerMetaDataLoading || !sessionPlayerData.start || !sessionPlayerData.end) {
                    return null
                }
                return { start: sessionPlayerData.start.valueOf(), end: sessionPlayerData.end.valueOf() }
            },
        ],
        playbackTimestamp: [
            (s) => [s.recordingTimestamp, s.recordingBounds],
            (recordingTimestamp: number | null, recordingBounds: RecordingBounds | null): number | null =>
                resolvePlaybackPosition(recordingTimestamp, recordingBounds).timestamp,
        ],
        exceptionOutsideEdge: [
            (s) => [s.exceptionTimestamp, s.recordingBounds],
            (exceptionTimestamp: number | null, recordingBounds: RecordingBounds | null): RecordingEdge | null =>
                resolvePlaybackPosition(exceptionTimestamp, recordingBounds).outsideEdge,
        ],
    }),
    listeners(({ actions, values }) => {
        const playFromSelectedTimestamp = (): void => {
            if (values.sessionPlayerMetaDataLoading || values.isNotFound) {
                return
            }
            if (values.playbackTimestamp) {
                actions.seekToTimestamp(values.playbackTimestamp)
            }
            actions.setPlay()
        }

        return {
            setRecordingTimestamp: playFromSelectedTimestamp,
            loadRecordingMetaSuccess: playFromSelectedTimestamp,
        }
    }),
    events(({ props, actions }) => ({
        afterMount: () => {
            if (props.timestamp) {
                actions.setRecordingTimestamp(dayjs(props.timestamp), 5000)
            }
        },
    })),
])
