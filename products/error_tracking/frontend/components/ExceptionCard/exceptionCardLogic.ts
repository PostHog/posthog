import { MakeLogicType, actions, kea, key, listeners, path, props, reducers, selectors } from 'kea'

import posthog from 'lib/posthog-typed'

export type LinkedDataKind = 'logs' | 'recording'

export interface ExceptionLinkedData {
    /** Whether this exception has linked logs, or null while the lookup runs. */
    hasLogs: boolean | null
    /** How many of the issue's exceptions have each kind of data, or null while the lookup runs. */
    exceptionCounts: Record<LinkedDataKind, number> | null
    showOnlyExceptionsWith: (kind: LinkedDataKind) => void
}

export type ExceptionCardLogicProps = {
    issueId: string
    loading: boolean
    logicKey?: string
    linkedData?: ExceptionLinkedData
}

export type ExceptionCardTab = 'stack_trace' | 'properties' | 'timeline' | 'recording' | 'logs'

export type ExceptionLogsScope = 'trace' | 'span' | 'session' | 'window'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface exceptionCardLogicValues {
    currentTab: ExceptionCardTab
    expandedFrameRawIds: Set<string>
    issueId: string
    linkedData: ExceptionLinkedData | null
    loading: boolean
    logsScope: ExceptionLogsScope
    propertyNameFilter: string
    showJSONProperties: boolean
    showUnlinkedLogs: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface exceptionCardLogicActions {
    setCurrentTab: (tab: ExceptionCardTab) => {
        tab: ExceptionCardTab
    }
    setFrameExpanded: (
        rawId: string,
        expanded: boolean
    ) => {
        expanded: boolean
        rawId: string
    }
    setLogsScope: (scope: ExceptionLogsScope) => {
        scope: ExceptionLogsScope
    }
    setPropertyNameFilter: (propertyNameFilter: string) => {
        propertyNameFilter: string
    }
    setShowJSONProperties: (showJSON: boolean) => {
        showJSON: boolean
    }
    setShowUnlinkedLogs: (showUnlinkedLogs: boolean) => {
        showUnlinkedLogs: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface exceptionCardLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        issueId: (issueId: string) => string
        loading: (loading: boolean) => boolean
        linkedData: (linkedData: ExceptionLinkedData | undefined) => ExceptionLinkedData | null
    }
}

export type exceptionCardLogicType = MakeLogicType<
    exceptionCardLogicValues,
    exceptionCardLogicActions,
    ExceptionCardLogicProps,
    exceptionCardLogicMeta
>

export const exceptionCardLogic = kea<exceptionCardLogicType>([
    path((key) => ['products', 'error_tracking', 'ExceptionCard', key]),
    key((props) => props.logicKey ?? props.issueId),
    props({} as ExceptionCardLogicProps),

    actions({
        setShowJSONProperties: (showJSON: boolean) => ({ showJSON }),
        setPropertyNameFilter: (propertyNameFilter: string) => ({ propertyNameFilter }),
        setCurrentTab: (tab: ExceptionCardTab) => ({ tab }),
        setFrameExpanded: (rawId: string, expanded: boolean) => ({ rawId, expanded }),
        setLogsScope: (scope: ExceptionLogsScope) => ({ scope }),
        setShowUnlinkedLogs: (showUnlinkedLogs: boolean) => ({ showUnlinkedLogs }),
    }),

    reducers({
        expandedFrameRawIds: [
            new Set<string>(),
            {
                setFrameExpanded: (state, { rawId, expanded }) => {
                    const has = state.has(rawId)
                    if (expanded === has) {
                        return state
                    }
                    const next = new Set(state)
                    if (expanded) {
                        next.add(rawId)
                    } else {
                        next.delete(rawId)
                    }
                    return next
                },
            },
        ],
        showJSONProperties: [
            false,
            {
                setShowJSONProperties: (_, { showJSON }) => showJSON,
            },
        ],
        propertyNameFilter: [
            '',
            {
                setPropertyNameFilter: (_, { propertyNameFilter }) => propertyNameFilter,
            },
        ],
        currentTab: [
            'stack_trace' as ExceptionCardTab,
            {
                setCurrentTab: (_, { tab }) => tab,
            },
        ],
        logsScope: [
            'trace' as ExceptionLogsScope,
            {
                setLogsScope: (_, { scope }) => scope,
            },
        ],
        showUnlinkedLogs: [
            false,
            {
                setShowUnlinkedLogs: (_, { showUnlinkedLogs }) => showUnlinkedLogs,
            },
        ],
    }),

    selectors({
        issueId: [(_, p) => [p.issueId], (issueId: string) => issueId],
        loading: [(_, p) => [p.loading], (loading: boolean) => loading],
        linkedData: [
            () => [(_, props) => props.linkedData],
            (linkedData: ExceptionLinkedData | undefined): ExceptionLinkedData | null => linkedData ?? null,
        ],
    }),

    listeners(({ props }) => ({
        setFrameExpanded: ({ expanded }) => {
            if (expanded) {
                posthog.capture('error_tracking_stacktrace_explored', { issue_id: props.issueId })
            }
        },
    })),
])
