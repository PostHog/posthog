import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'

import { FEATURE_FLAGS } from 'lib/constants'
import { type FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import posthog from 'lib/posthog-typed'
import { getAccessControlDisabledReason } from 'lib/utils/accessControlUtils'

import { AccessControlLevel, AccessControlResourceType } from '~/types'

export type ExceptionCardLogicProps = {
    issueId: string
    loading: boolean
    logicKey?: string
    onShowOnlyWithRecording?: () => void
}

export type ExceptionCardTab = 'stack_trace' | 'properties' | 'timeline' | 'recording' | 'logs' | 'trace'

export type ExceptionLogsScope = 'trace' | 'span' | 'session' | 'window'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface exceptionCardLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentTab: ExceptionCardTab
    expandedFrameRawIds: Set<string>
    issueId: string
    loading: boolean
    logsEnabled: boolean
    logsScope: ExceptionLogsScope
    onShowOnlyWithRecording: (() => void) | null
    propertyNameFilter: string
    showJSONProperties: boolean
    traceTabEnabled: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface exceptionCardLogicActions {
    setCurrentTab: (tab: ExceptionCardTab) => {
        tab: ExceptionCardTab
    }
    setFrameExpanded: (
        rawId: string,
        expanded: boolean
    ) => {
        expanded: boolean
        rawId: string
    }
    setLogsScope: (scope: ExceptionLogsScope) => {
        scope: ExceptionLogsScope
    }
    setPropertyNameFilter: (propertyNameFilter: string) => {
        propertyNameFilter: string
    }
    setShowJSONProperties: (showJSON: boolean) => {
        showJSON: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface exceptionCardLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        issueId: (issueId: string) => string
        logsEnabled: (featureFlags: FeatureFlagsSet) => boolean
        traceTabEnabled: (logsEnabled: boolean) => boolean
        loading: (loading: boolean) => boolean
        onShowOnlyWithRecording: (arg: any) => (() => void) | null
    }
}

export type exceptionCardLogicType = MakeLogicType<
    exceptionCardLogicValues,
    exceptionCardLogicActions,
    ExceptionCardLogicProps,
    exceptionCardLogicMeta
>

export const exceptionCardLogic = kea<exceptionCardLogicType>([
    path((key) => ['products', 'error_tracking', 'ExceptionCard', key]),
    key((props) => props.logicKey ?? props.issueId),
    props({} as ExceptionCardLogicProps),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),

    actions({
        setShowJSONProperties: (showJSON: boolean) => ({ showJSON }),
        setPropertyNameFilter: (propertyNameFilter: string) => ({ propertyNameFilter }),
        setCurrentTab: (tab: ExceptionCardTab) => ({ tab }),
        setFrameExpanded: (rawId: string, expanded: boolean) => ({ rawId, expanded }),
        setLogsScope: (scope: ExceptionLogsScope) => ({ scope }),
    }),

    reducers({
        expandedFrameRawIds: [
            new Set<string>(),
            {
                setFrameExpanded: (state, { rawId, expanded }) => {
                    const has = state.has(rawId)
                    if (expanded === has) {
                        return state
                    }
                    const next = new Set(state)
                    if (expanded) {
                        next.add(rawId)
                    } else {
                        next.delete(rawId)
                    }
                    return next
                },
            },
        ],
        showJSONProperties: [
            false,
            {
                setShowJSONProperties: (_, { showJSON }) => showJSON,
            },
        ],
        propertyNameFilter: [
            '',
            {
                setPropertyNameFilter: (_, { propertyNameFilter }) => propertyNameFilter,
            },
        ],
        currentTab: [
            'stack_trace' as ExceptionCardTab,
            {
                setCurrentTab: (_, { tab }) => tab,
            },
        ],
        logsScope: [
            'trace' as ExceptionLogsScope,
            {
                setLogsScope: (_, { scope }) => scope,
            },
        ],
    }),

    selectors({
        issueId: [(_, p) => [p.issueId], (issueId: string) => issueId],
        logsEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.LOGS_IN_ERROR_TRACKING],
        ],
        // Ships with the Logs tab under its flag, and hides without Tracing access as ViewTraceButton does.
        traceTabEnabled: [
            (s) => [s.logsEnabled],
            (logsEnabled: boolean): boolean =>
                logsEnabled &&
                !getAccessControlDisabledReason(AccessControlResourceType.Tracing, AccessControlLevel.Viewer),
        ],
        loading: [(_, p) => [p.loading], (loading: boolean) => loading],
        onShowOnlyWithRecording: [
            () => [(_, props) => props.onShowOnlyWithRecording],
            (onShowOnlyWithRecording: (() => void) | undefined): (() => void) | null => onShowOnlyWithRecording ?? null,
        ],
    }),

    listeners(({ props }) => ({
        // Pinned: analytics event name and `tab` values. Renaming one breaks the dashboards built on it.
        setCurrentTab: ({ tab }) => {
            posthog.capture('error_tracking_exception_tab_changed', { issue_id: props.issueId, tab })
        },
        setFrameExpanded: ({ expanded }) => {
            if (expanded) {
                posthog.capture('error_tracking_stacktrace_explored', { issue_id: props.issueId })
            }
        },
    })),
])
