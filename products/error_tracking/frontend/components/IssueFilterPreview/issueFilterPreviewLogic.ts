export const issueFilterPreviewLogic = kea<issueFilterPreviewLogicType>([
    path(['products', 'error_tracking', 'components', 'IssueFilterPreview', 'issueFilterPreviewLogic']),
    connect(() => ({
        values: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['dateRange', 'filterGroup', 'filterTestAccounts', 'searchQuery'],
            quickFiltersSectionLogic({
                context: QuickFilterContext.ErrorTrackingIssueFilters,
                logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY,
            }),
            ['selectedQuickFilters'],
        ],
        actions: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['addPropertyFilter', 'setDateRange', 'setFilterGroup', 'setFilterTestAccounts', 'setSearchQuery'],
            quickFiltersSectionLogic({
                context: QuickFilterContext.ErrorTrackingIssueFilters,
                logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY,
            }),
            ['clearQuickFilter'],
        ],
    })),
    actions({
        setActivePreview: (activePreview: IssueFilterPreview) => ({ activePreview }),
        applyDateRangeFilter: (dateRange: DateRange) => ({ dateRange }),
        applyPropertyFilter: (
            key: string,
            value: string | number | boolean | null,
            operator: PropertyOperator = PropertyOperator.Exact,
            replaceExisting: boolean = false
        ) => ({ key, value, operator, replaceExisting }),
        undoActivePreview: true,
        clearNonDateFilters: true,
        popDateRangeHistory: true,
        popFilterGroupHistory: true,
        pushDateRangeHistory: (dateRange: DateRange) => ({ dateRange }),
        pushFilterGroupHistory: (filterGroup: UniversalFiltersGroup) => ({ filterGroup }),
    }),
    reducers({
        activePreview: [
            'time' as IssueFilterPreview,
            {
                setActivePreview: (_, { activePreview }) => activePreview,
            },
        ],
        dateRangeHistory: [
            [] as DateRange[],
            {
                pushDateRangeHistory: (history, { dateRange }) => [...history, dateRange],
                popDateRangeHistory: (history) => history.slice(0, -1),
                // A manual date change (not from a preview) invalidates the undo stack.
                setDateRange: (history, { fromPreview }) => (fromPreview ? history : []),
            },
        ],
        filterGroupHistory: [
            [] as UniversalFiltersGroup[],
            {
                pushFilterGroupHistory: (history, { filterGroup }) => [...history, filterGroup],
                popFilterGroupHistory: (history) => history.slice(0, -1),
                clearNonDateFilters: () => [],
                // A manual filter edit (not from a preview) invalidates the undo stack.
                setFilterGroup: (history, { filterAddedFromPreview }) => (filterAddedFromPreview ? history : []),
            },
        ],
    }),
    selectors({
        canUndoActivePreview: [
            (s) => [s.activePreview, s.dateRangeHistory, s.filterGroupHistory],
            (
                activePreview: IssueFilterPreview,
                dateRangeHistory: DateRange[],
                filterGroupHistory: UniversalFiltersGroup[]
            ): boolean => (activePreview === 'time' ? dateRangeHistory.length > 0 : filterGroupHistory.length > 0),
        ],
        hasActiveFilters: [
            (s) => [s.filterGroup, s.filterTestAccounts, s.searchQuery, s.selectedQuickFilters],
            (
                filterGroup: UniversalFiltersGroup,
                filterTestAccounts: boolean,
                searchQuery: string,
                selectedQuickFilters: Record<string, SelectedQuickFilter>
            ): boolean => {
                const firstValue = filterGroup.values[0]
                const hasPropertyFilters =
                    firstValue !== undefined &&
                    ('values' in firstValue ? firstValue.values.length > 0 : filterGroup.values.length > 0)
                return (
                    hasPropertyFilters ||
                    filterTestAccounts !== DEFAULT_TEST_ACCOUNT ||
                    searchQuery !== DEFAULT_SEARCH_QUERY ||
                    Object.keys(selectedQuickFilters).length > 0
                )
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        applyDateRangeFilter: ({ dateRange }) => {
            actions.pushDateRangeHistory(values.dateRange)
            actions.setDateRange(dateRange, true)
        },
        applyPropertyFilter: ({ key, value, operator, replaceExisting }) => {
            const previousFilterGroup = values.filterGroup
            actions.addPropertyFilter(key, value, operator, false, replaceExisting)
            if (values.filterGroup !== previousFilterGroup) {
                actions.pushFilterGroupHistory(previousFilterGroup)
            }
        },
        undoActivePreview: () => {
            const previousDateRange = values.dateRangeHistory.at(-1)
            const previousFilterGroup = values.filterGroupHistory.at(-1)
            if (values.activePreview === 'time' && previousDateRange) {
                actions.setDateRange(previousDateRange, true)
                actions.popDateRangeHistory()
            } else if (values.activePreview !== 'time' && previousFilterGroup) {
                actions.setFilterGroup(previousFilterGroup, 1)
                actions.popFilterGroupHistory()
            }
        },
        clearNonDateFilters: () => {
            actions.setFilterGroup(DEFAULT_FILTER_GROUP)
            actions.setFilterTestAccounts(DEFAULT_TEST_ACCOUNT)
            actions.setSearchQuery(DEFAULT_SEARCH_QUERY)
            for (const filterId of Object.keys(values.selectedQuickFilters)) {
                actions.clearQuickFilter(filterId)
            }
        },
    })),
])
