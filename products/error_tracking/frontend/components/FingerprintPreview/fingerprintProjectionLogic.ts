import { MakeLogicType, events, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import type { ScatterSeries } from '@posthog/quill-charts'

import api from 'lib/api'
import { midEllipsis } from 'lib/utils/strings'

import type { ErrorTrackingFingerprintProjectionQueryResponse } from '~/queries/schema/schema-general'

import { errorTrackingFingerprintProjectionQuery } from '../../queries'

export interface FingerprintProjectionLogicProps {
    issueId: string
}

export interface FingerprintPointMeta {
    fingerprint: string
}

export interface FingerprintProjectionDomains {
    x: readonly [number, number]
    y: readonly [number, number]
}

function centeredDomain(values: number[]): readonly [number, number] {
    const center = values.reduce((sum, value) => sum + value, 0) / values.length
    const radius = Math.max(...values.map((value) => Math.abs(value - center)), 1)
    const paddedRadius = radius * 1.1
    return [center - paddedRadius, center + paddedRadius]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface fingerprintProjectionLogicValues {
    fingerprintDomains: FingerprintProjectionDomains | null
    fingerprintSeries: ScatterSeries<FingerprintPointMeta>[]
    projection: ErrorTrackingFingerprintProjectionQueryResponse
    projectionError: string | null
    projectionLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface fingerprintProjectionLogicActions {
    loadProjection: () => any
    loadProjectionFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadProjectionSuccess: (
        projection: ErrorTrackingFingerprintProjectionQueryResponse,
        payload?: any
    ) => {
        projection: ErrorTrackingFingerprintProjectionQueryResponse
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface fingerprintProjectionLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        fingerprintDomains: (
            projection: ErrorTrackingFingerprintProjectionQueryResponse
        ) => FingerprintProjectionDomains | null
        fingerprintSeries: (
            projection: ErrorTrackingFingerprintProjectionQueryResponse
        ) => ScatterSeries<FingerprintPointMeta>[]
    }
}

export type fingerprintProjectionLogicType = MakeLogicType<
    fingerprintProjectionLogicValues,
    fingerprintProjectionLogicActions,
    FingerprintProjectionLogicProps,
    fingerprintProjectionLogicMeta
>

export const fingerprintProjectionLogic = kea<fingerprintProjectionLogicType>([
    path((key) => [
        'products',
        'error_tracking',
        'components',
        'FingerprintPreview',
        'fingerprintProjectionLogic',
        key,
    ]),
    props({} as FingerprintProjectionLogicProps),
    key(({ issueId }) => issueId),
    loaders(({ props }) => ({
        projection: [
            { results: [] } as ErrorTrackingFingerprintProjectionQueryResponse,
            {
                loadProjection: async () =>
                    (await api.query(
                        errorTrackingFingerprintProjectionQuery(props.issueId)
                    )) as ErrorTrackingFingerprintProjectionQueryResponse,
            },
        ],
    })),
    reducers({
        projectionError: [
            null as string | null,
            {
                loadProjection: () => null,
                loadProjectionSuccess: () => null,
                loadProjectionFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        fingerprintDomains: [
            (selectors) => [selectors.projection],
            (projection: ErrorTrackingFingerprintProjectionQueryResponse): FingerprintProjectionDomains | null => {
                if (projection.results.length === 0) {
                    return null
                }

                return {
                    x: centeredDomain(projection.results.map((point) => point.x)),
                    y: centeredDomain(projection.results.map((point) => point.y)),
                }
            },
        ],
        fingerprintSeries: [
            (selectors) => [selectors.projection],
            (projection: ErrorTrackingFingerprintProjectionQueryResponse): ScatterSeries<FingerprintPointMeta>[] => [
                {
                    key: 'fingerprints',
                    label: 'Fingerprints',
                    points: projection.results.map((point) => ({
                        x: point.x,
                        y: point.y,
                        label: midEllipsis(point.fingerprint, 24),
                        meta: { fingerprint: point.fingerprint },
                    })),
                },
            ],
        ],
    }),
    events(({ actions }) => ({
        afterMount: () => actions.loadProjection(),
    })),
])
