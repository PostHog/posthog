export interface similarFingerprintsLogicValues {
    originFingerprint: string | null
    originFirstSeen: string | null
    similar: SimilarFingerprint[]
    similarLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface similarFingerprintsLogicActions {
    closeSimilar: () => {
        value: true
    }
    loadSimilar: () => any
    loadSimilarFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSimilarSuccess: (
        similar: SimilarFingerprint[],
        payload?: any
    ) => {
        payload?: any
        similar: SimilarFingerprint[]
    }
    openSimilar: (
        fingerprint: string,
        firstSeen: string
    ) => {
        fingerprint: string
        firstSeen: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface similarFingerprintsLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: Record<string, never>
}

export type similarFingerprintsLogicType = MakeLogicType<
    similarFingerprintsLogicValues,
    similarFingerprintsLogicActions,
    SimilarFingerprintsLogicProps,
    similarFingerprintsLogicMeta
>

export const similarFingerprintsLogic = kea<similarFingerprintsLogicType>([
    path((key) => ['products', 'error_tracking', 'components', 'FingerprintPreview', 'similarFingerprintsLogic', key]),
    props({} as SimilarFingerprintsLogicProps),
    key(({ issueId }) => issueId),

    actions({
        openSimilar: (fingerprint: string, firstSeen: string) => ({ fingerprint, firstSeen }),
        closeSimilar: true,
    }),

    reducers({
        originFingerprint: [
            null as string | null,
            {
                openSimilar: (_, { fingerprint }) => fingerprint,
                closeSimilar: () => null,
            },
        ],
        originFirstSeen: [
            null as string | null,
            {
                openSimilar: (_, { firstSeen }) => firstSeen,
                closeSimilar: () => null,
            },
        ],
    }),

    loaders(({ values }) => ({
        similar: [
            [] as SimilarFingerprint[],
            {
                closeSimilar: () => [],
                loadSimilar: async () => {
                    const { originFingerprint, originFirstSeen } = values
                    if (!originFingerprint || !originFirstSeen) {
                        return []
                    }

                    const similarity = (await api.query(
                        errorTrackingDocumentSimilarityQuery({
                            documentId: originFingerprint,
                            timestamp: originFirstSeen,
                            limit: MAX_SIMILAR + 1,
                        })
                    )) as DocumentSimilarityQueryResponse

                    const distances = similarity.results
                        .filter(({ result }) => result.document_id !== originFingerprint)
                        .slice(0, MAX_SIMILAR)
                    if (distances.length === 0) {
                        return []
                    }

                    const fingerprints = distances.map(({ result }) => result.document_id)
                    const hydration = await api.queryHogQL(
                        errorTrackingFingerprintSamplesQuery(
                            fingerprints,
                            dayjs().subtract(HYDRATION_DAYS, 'day').toISOString()
                        ),
                        { scene: 'ErrorTrackingSimilarFingerprints', productKey: 'error_tracking' }
                    )

                    const hydrated: Record<string, { issueId: string | null; sample?: FingerprintSample }> = {}
                    for (const [fingerprint, issueId, samples] of hydration.results as [
                        string,
                        string | null,
                        FingerprintSample[],
                    ][]) {
                        const sample = samples?.[0]
                        hydrated[fingerprint] = {
                            issueId: issueId ?? null,
                            sample: sample?.type || sample?.value ? sample : undefined,
                        }
                    }

                    return distances.map(({ result, distance }) => ({
                        fingerprint: result.document_id,
                        similarity: toSimilarityScore(distance),
                        issueId: hydrated[result.document_id]?.issueId ?? null,
                        sample: hydrated[result.document_id]?.sample,
                    }))
                },
            },
        ],
    })),

    listeners(({ actions }) => ({
        openSimilar: () => actions.loadSimilar(),
    })),
])
