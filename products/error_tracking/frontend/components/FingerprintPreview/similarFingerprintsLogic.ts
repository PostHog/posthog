import { MakeLogicType, actions, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import { dayjs } from 'lib/dayjs'

import { DocumentSimilarityQueryResponse } from '~/queries/schema/schema-general'

import { errorTrackingDocumentSimilarityQuery, errorTrackingFingerprintSamplesQuery } from '../../queries'
import { FingerprintSample } from './fingerprintSamplesLogic'

// Bounds both the similarity result set and the fingerprint list the hydration query scans.
const MAX_SIMILAR = 20
// The hydration query has no issue to scope by, so it needs a time bound to stay cheap.
const HYDRATION_DAYS = 30

export interface SimilarFingerprintsLogicProps {
    issueId: string
}

export interface SimilarFingerprint {
    fingerprint: string
    similarity: number
    issueId: string | null
    sample?: FingerprintSample
}

export function toSimilarityScore(distance: number): number {
    // Cosine distance runs 0..2, so the low end clamps rather than going negative. Rounded to 5s
    // because the underlying embedding distance is not precise enough to justify finer steps.
    return Math.max(0, Math.min(100, Math.round((1 - distance) * 20) * 5))
}

