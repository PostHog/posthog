// Bounds the sample-event lookup to a window around when the fingerprint was first seen.
const EVENT_WINDOW_MINUTES = 30

export interface ManageFingerprintsLogicProps {
    issueId: string
}

export function getUnmergeDisabledReason(
    fingerprintCount: number,
    selectedCount: number,
    fingerprintsLoading: boolean,
    unmerging: boolean
): string | null {
    if (unmerging) {
        return 'Unmerging in progress'
    }
    if (fingerprintsLoading) {
        return 'Wait for fingerprints to finish loading'
    }
    if (fingerprintCount < 2) {
        return 'This issue only has one fingerprint and cannot be unmerged'
    }
    if (selectedCount === 0) {
        return 'Select at least one fingerprint to unmerge'
    }
    // Splitting every fingerprint out would leave the original issue with nothing in it.
    if (selectedCount === fingerprintCount) {
        return 'Leave at least one fingerprint on this issue'
    }
    return null
}

