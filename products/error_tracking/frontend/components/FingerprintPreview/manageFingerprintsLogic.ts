export const manageFingerprintsLogic = kea<manageFingerprintsLogicType>([
    path((key) => ['products', 'error_tracking', 'components', 'FingerprintPreview', 'manageFingerprintsLogic', key]),
    props({} as ManageFingerprintsLogicProps),
    key(({ issueId }) => issueId),

    connect((props: ManageFingerprintsLogicProps) => ({
        values: [
            errorTrackingIssueSceneLogic({ id: props.issueId }),
            ['issue', 'issueFingerprints', 'issueFingerprintsLoading'],
            fingerprintSamplesLogic({ issueId: props.issueId }),
            ['samples', 'samplesLoading'],
        ],
        actions: [
            errorTrackingIssueSceneLogic({ id: props.issueId }),
            ['loadIssueFingerprints', 'loadIssueFingerprintsSuccess'],
            issueActionsLogic,
            ['splitIssue', 'splitIssueSuccess', 'mutationFailure'],
        ],
    })),

    actions({
        openManage: true,
        closeManage: true,
        toggleFingerprint: (fingerprint: string) => ({ fingerprint }),
        setActiveFingerprint: (fingerprint: string) => ({ fingerprint }),
        loadActiveEvent: (fingerprint: string) => ({ fingerprint }),
        retryActiveEvent: true,
        unmergeSelected: true,
    }),

    reducers(({ props }) => ({
        isOpen: [
            false,
            {
                openManage: () => true,
                closeManage: () => false,
            },
        ],
        selected: [
            [] as string[],
            {
                openManage: () => [],
                closeManage: () => [],
                splitIssueSuccess: (state, { id }) => (id === props.issueId ? [] : state),
                toggleFingerprint: (state, { fingerprint }) =>
                    state.includes(fingerprint) ? state.filter((f) => f !== fingerprint) : [...state, fingerprint],
            },
        ],
        activeFingerprint: [
            null as string | null,
            {
                setActiveFingerprint: (_, { fingerprint }) => fingerprint,
                closeManage: () => null,
            },
        ],
        unmerging: [
            false,
            {
                unmergeSelected: () => true,
                splitIssueSuccess: (state, { id }) => (id === props.issueId ? false : state),
                mutationFailure: (state, { mutationName, issueId }) =>
                    mutationName === 'splitIssues' && issueId === props.issueId ? false : state,
                closeManage: () => false,
            },
        ],
        activeEventError: [
            null as string | null,
            {
                loadActiveEvent: () => null,
                loadActiveEventSuccess: () => null,
                loadActiveEventFailure: (_, { error }) => error,
                closeManage: () => null,
            },
        ],
    })),

    loaders(({ values }) => ({
        activeEvent: [
            null as ErrorEventType | null,
            {
                loadActiveEvent: async ({ fingerprint }, breakpoint) => {
                    const firstSeen = values.issueFingerprints.find(
                        (f: ErrorTrackingFingerprint) => f.fingerprint === fingerprint
                    )?.created_at
                    const response = await api.query(
                        errorTrackingFingerprintEventQuery({
                            fingerprint,
                            after: firstSeen
                                ? dayjs(firstSeen).subtract(EVENT_WINDOW_MINUTES, 'minute').toISOString()
                                : undefined,
                            before: firstSeen
                                ? dayjs(firstSeen).add(EVENT_WINDOW_MINUTES, 'minute').toISOString()
                                : undefined,
                        })
                    )
                    breakpoint()
                    const row = response.results[0]
                    if (!row) {
                        return null
                    }
                    const [uuid, properties, timestamp, distinctId] = row
                    return {
                        event: '$exception',
                        uuid,
                        timestamp,
                        distinct_id: distinctId,
                        person: { distinct_ids: [], properties: {} },
                        properties: typeof properties === 'string' ? JSON.parse(properties) : properties,
                    } as ErrorEventType
                },
            },
        ],
    })),

    selectors({
        unmergeDisabledReason: [
            (s) => [s.issueFingerprints, s.issueFingerprintsLoading, s.selected, s.samplesLoading, s.unmerging],
            (
                issueFingerprints: ErrorTrackingFingerprint[],
                issueFingerprintsLoading: boolean,
                selected: string[],
                samplesLoading: boolean,
                unmerging: boolean
            ): string | null =>
                getUnmergeDisabledReason(
                    issueFingerprints.length,
                    selected.length,
                    issueFingerprintsLoading || samplesLoading,
                    unmerging
                ),
        ],
    }),

    listeners(({ actions, props, values }) => {
        function previewFirstFingerprint(): void {
            if (!values.isOpen || values.activeFingerprint) {
                return
            }
            const first = values.issueFingerprints[0]
            if (first) {
                actions.setActiveFingerprint(first.fingerprint)
            }
        }
        return {
            setActiveFingerprint: ({ fingerprint }) => actions.loadActiveEvent(fingerprint),
            retryActiveEvent: () => {
                if (values.activeFingerprint) {
                    actions.loadActiveEvent(values.activeFingerprint)
                }
            },
            // Preview the first fingerprint so the detail pane is not blank. The modal can open before
            // the scene has loaded its fingerprints, so this has to run on both events.
            openManage: () => previewFirstFingerprint(),
            closeManage: () => {
                if (router.values.searchParams.manageFingerprints) {
                    const { manageFingerprints: _, ...searchParams } = router.values.searchParams
                    router.actions.replace(
                        router.values.currentLocation.pathname,
                        searchParams,
                        router.values.hashParams
                    )
                }
            },
            loadIssueFingerprintsSuccess: () => previewFirstFingerprint(),
            unmergeSelected: () => {
                actions.splitIssue(
                    props.issueId,
                    values.selected.map((fingerprint) => {
                        const sample = values.samples[fingerprint]
                        return {
                            fingerprint,
                            ...(sample?.type || values.issue?.name
                                ? { name: sample?.type ?? values.issue?.name ?? undefined }
                                : {}),
                            ...(sample?.value || values.issue?.description
                                ? { description: sample?.value ?? values.issue?.description ?? undefined }
                                : {}),
                        }
                    })
                )
            },
            splitIssueSuccess: ({ id, newIssueIds }) => {
                if (id !== props.issueId || !values.isOpen) {
                    return
                }
                actions.closeManage()
                actions.loadIssueFingerprints()
                fingerprintProjectionLogic.findMounted({ issueId: props.issueId })?.actions.loadProjection()
                if (newIssueIds.length === 0) {
                    lemonToast.warning('No fingerprints were unmerged')
                } else if (newIssueIds.length === 1) {
                    lemonToast.success('Fingerprint unmerged', {
                        button: {
                            label: 'View issue',
                            action: () => router.actions.push(urls.errorTrackingIssue(newIssueIds[0])),
                        },
                    })
                } else {
                    lemonToast.success(`${newIssueIds.length} fingerprints unmerged`)
                }
            },
            mutationFailure: ({ mutationName, issueId }) => {
                if (mutationName === 'splitIssues' && issueId === props.issueId && values.isOpen) {
                    lemonToast.error('Could not unmerge the selected fingerprints. Try again.')
                }
            },
        }
    }),

    urlToAction(({ actions, props }) => ({
        '/error_tracking/:id': ({ id }, searchParams) => {
            if (id === props.issueId && searchParams.manageFingerprints === 'true') {
                actions.openManage()
            }
        },
    })),
])
