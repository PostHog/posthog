export type issueActionsLogicType = MakeLogicType<issueActionsLogicValues, issueActionsLogicActions>

export const issueActionsLogic = kea<issueActionsLogicType>([
    path(['products', 'error_tracking', 'components', 'IssueActions', 'issueActionsLogic']),

    actions({
        mergeIssues: (ids: string[]) => ({ ids }),
        splitIssue: (
            id: ErrorTrackingIssue['id'],
            fingerprints: { fingerprint: string; name?: string; description?: string }[]
        ) => ({
            id,
            fingerprints,
        }),
        resolveIssues: (ids: string[]) => ({ ids }),
        suppressIssues: (ids: string[]) => ({ ids }),
        activateIssues: (ids: string[]) => ({ ids }),
        assignIssues: (ids: string[], assignee: ErrorTrackingIssue['assignee']) => ({ ids, assignee }),

        updateIssueAssignee: (id: string, assignee: ErrorTrackingIssue['assignee']) => ({ id, assignee }),
        updateIssueStatus: (id: string, status: ErrorTrackingIssue['status']) => ({ id, status }),
        updateIssueSeverity: (id: string, severity: ErrorTrackingQueryIssueSeverity | null) => ({ id, severity }),
        finishIssueSeverityUpdate: (id: string) => ({ id }),
        updateIssueName: (id: string, name: string) => ({ id, name }),
        updateIssueDescription: (id: string, description: string) => ({ id, description }),
        createIssueCohort: (id: string, name: string, description: string) => ({ id, name, description }),

        splitIssueSuccess: (newIssueIds: string[]) => ({ newIssueIds }),
        mergeIssuesSuccess: (primaryId: string, targetId: string, merged: boolean) => ({
            primaryId,
            targetId,
            merged,
        }),
        mutationSuccess: (mutationName: string) => ({ mutationName }),
        mutationFailure: (mutationName: string, error: unknown) => ({ mutationName, error }),
        clearNeedsReload: true,
    }),

    reducers({
        needsReload: [
            false,
            {
                mutationSuccess: () => true,
                clearNeedsReload: () => false,
            },
        ],
        severityUpdateInFlightIds: [
            [] as string[],
            {
                updateIssueSeverity: (state, { id }) => (state.includes(id) ? state : [...state, id]),
                finishIssueSeverityUpdate: (state, { id }) => state.filter((issueId) => issueId !== id),
            },
        ],
    }),

    listeners(({ actions }) => {
        async function runMutation<T>(
            mutationName: string,
            cb: () => Promise<T>,
            onSuccess?: (result: T) => Promise<void>
        ): Promise<void> {
            try {
                const result = await cb()
                if (onSuccess) {
                    await onSuccess(result)
                }
                actions.mutationSuccess(mutationName)
            } catch (e: unknown) {
                actions.mutationFailure(mutationName, e)
            }
        }
        return {
            mergeIssues: async ({ ids }) => {
                const [firstId, ...otherIds] = ids
                if (firstId && otherIds.length > 0) {
                    await runMutation(
                        'mergeIssues',
                        async () => {
                            posthog.capture('error_tracking_issue_merged', { primary: firstId })
                            // The issues route is nested under team_id, so the path segment is the
                            // active environment, not the project it belongs to.
                            return await errorTrackingIssuesMergeCreate(
                                String(teamLogic.values.currentTeamIdStrict),
                                firstId,
                                { ids: otherIds }
                            )
                        },
                        async ({ success, target_issue_id }) => {
                            // The backend merges into another selected issue when the first one was
                            // merged away already, so the overlay follows the issue it wrote into.
                            const targetId = target_issue_id || firstId
                            await pendingUpdateActions()?.captureMergePendingUpdates(
                                targetId,
                                ids.filter((id) => id !== targetId)
                            )
                            // Announced after the overlay, because a reload without it reads the
                            // merged rows back out of ClickHouse.
                            actions.mergeIssuesSuccess(firstId, targetId, success)
                        }
                    )
                }
            },
            splitIssue: async ({ id, fingerprints }) => {
                await runMutation('splitIssues', async () => {
                    posthog.capture('error_tracking_issue_split', { issueId: id })
                    const response = await api.errorTracking.split(id, fingerprints)
                    actions.splitIssueSuccess(response.new_issue_ids)
                })
            },
            resolveIssues: async ({ ids }) => {
                await runMutation('resolveIssues', async () => {
                    posthog.capture('error_tracking_issue_bulk_resolve')
                    await api.errorTracking.bulkMarkStatus(ids, 'resolved')
                })

                globalSetupLogic.findMounted()?.actions.markTaskAsCompleted(SetupTaskId.ResolveFirstError)
            },
            suppressIssues: async ({ ids }) => {
                await runMutation('suppressIssues', async () => {
                    posthog.capture('error_tracking_issue_bulk_suppress')
                    await api.errorTracking.bulkMarkStatus(ids, 'suppressed')
                })
            },
            activateIssues: async ({ ids }) => {
                await runMutation('activateIssues', async () => {
                    posthog.capture('error_tracking_issue_bulk_activate')
                    await api.errorTracking.bulkMarkStatus(ids, 'active')
                })
            },
            assignIssues: async ({ ids, assignee }) => {
                await runMutation('assignIssues', async () => {
                    posthog.capture('error_tracking_issue_bulk_assign')
                    await api.errorTracking.bulkAssign(ids, assignee)
                })
            },
            updateIssueAssignee: async ({ id, assignee }) => {
                await runMutation('updateIssueAssignee', async () => {
                    posthog.capture('error_tracking_issue_update_assignee')
                    await api.errorTracking.assignIssue(id, assignee)
                })
            },
            updateIssueStatus: async ({ id, status }) => {
                await runMutation('updateIssueStatus', async () => {
                    posthog.capture('error_tracking_issue_update_status', {
                        status,
                        issue_id: id,
                        source: 'issue_actions',
                    })
                    await api.errorTracking.updateIssue(id, { status })
                })
            },
            updateIssueSeverity: async ({ id, severity }) => {
                await runMutation('updateIssueSeverity', async () => {
                    posthog.capture('error_tracking_issue_update_severity', {
                        severity,
                        issue_id: id,
                        source: 'issue_actions',
                    })
                    await errorTrackingIssuesPartialUpdate(String(teamLogic.values.currentProjectId), id, {
                        severity,
                    })
                })
                actions.finishIssueSeverityUpdate(id)
            },
            updateIssueName: async ({ id, name }) => {
                await runMutation('updateIssueName', async () => {
                    posthog.capture('error_tracking_issue_update_name')
                    await api.errorTracking.updateIssue(id, { name })
                })
            },
            updateIssueDescription: async ({ id, description }) => {
                await runMutation('updateIssueDescription', async () => {
                    posthog.capture('error_tracking_issue_update_description')
                    await api.errorTracking.updateIssue(id, { description })
                })
            },
            createIssueCohort: async ({ id, name, description }) => {
                await runMutation('createIssueCohort', async () => {
                    let cohortParams = createCohortParams(name, description, id)
                    let formData = createCohortFormData(cohortParams)
                    let cohort = await api.cohorts.create(formData as Partial<CohortType>)
                    posthog.capture('error_tracking_issue_create_cohort', {
                        issueId: id,
                        cohortId: cohort.id,
                    })
                    await api.errorTracking.assignCohort(id, cohort.id)
                })
            },
            mutationSuccess: ({ mutationName }) => {
                if (mutationName === 'updateIssueAssignee' || mutationName === 'assignIssues') {
                    tryShowMCPHint('error_tracking.assign')
                }
                // The cohort dialog cannot see whether the mutation failed, so it must not
                // announce the cohort itself.
                if (mutationName === 'createIssueCohort') {
                    lemonToast.success('Cohort created')
                }
            },
            mergeIssuesSuccess: ({ merged }) => {
                if (!merged) {
                    lemonToast.info('These issues were merged already. The list now shows the current issues.')
                }
            },
            mutationFailure: ({ mutationName, error }) => {
                lemonToast.error(mutationFailureMessage(mutationName, error))
            },
        }
    }),
])

const MUTATION_FAILURE_MESSAGES: Record<string, string> = {
    mergeIssues: 'Could not merge these issues.',
    splitIssues: 'Could not unmerge this fingerprint.',
    resolveIssues: 'Could not resolve these issues.',
    suppressIssues: 'Could not suppress these issues.',
    activateIssues: 'Could not activate these issues.',
    assignIssues: 'Could not assign these issues.',
    updateIssueAssignee: 'Could not assign this issue.',
    updateIssueStatus: 'Could not update the status of this issue.',
    updateIssueSeverity: 'Could not update the severity of this issue.',
    updateIssueName: 'Could not rename this issue.',
    updateIssueDescription: 'Could not update the description of this issue.',
    createIssueCohort: 'Could not create a cohort for this issue.',
}

function mutationFailureMessage(mutationName: string, error: unknown): string {
    const failed = MUTATION_FAILURE_MESSAGES[mutationName] ?? 'Could not update these issues.'
    const detail = error instanceof ApiError ? error.detail : null
    return detail ? `${failed} ${detail}` : `${failed} Try again, and if it keeps happening contact support.`
}

function createCohortParams(name: string, description: string, issueId: string): CohortType {
    return {
        id: 'new',
        name,
        description,
        groups: [],
        filters: {
            properties: {
                type: FilterLogicalOperator.Or,
                values: [
                    {
                        type: FilterLogicalOperator.Or,
                        values: [
                            {
                                key: '$exception',
                                type: BehavioralFilterKey.Behavioral,
                                value: BehavioralEventType.PerformEvent,
                                negation: false,
                                event_type: TaxonomicFilterGroupType.Events,
                                event_filters: [
                                    {
                                        key: `issue_id = ${escapeHogQLString(issueId)}`,
                                        type: PropertyFilterType.HogQL,
                                    },
                                ],
                                explicit_datetime: '-30d',
                            },
                        ],
                    },
                ],
            },
        },
    }
}
