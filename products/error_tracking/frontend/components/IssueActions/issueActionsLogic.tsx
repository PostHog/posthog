export const issueActionsLogic = kea<issueActionsLogicType>([
    path(['products', 'error_tracking', 'components', 'IssueActions', 'issueActionsLogic']),

    actions({
        mergeIssues: (ids: string[]) => ({ ids }),
        splitIssue: (
            id: ErrorTrackingIssue['id'],
            fingerprints: { fingerprint: string; name?: string; description?: string }[]
        ) => ({
            id,
            fingerprints,
        }),
        resolveIssues: (ids: string[]) => ({ ids }),
        suppressIssues: (ids: string[]) => ({ ids }),
        activateIssues: (ids: string[]) => ({ ids }),
        assignIssues: (ids: string[], assignee: ErrorTrackingIssue['assignee']) => ({ ids, assignee }),

        updateIssueAssignee: (id: string, assignee: ErrorTrackingIssue['assignee']) => ({ id, assignee }),
        updateIssueStatus: (id: string, status: ErrorTrackingIssue['status']) => ({ id, status }),
        updateIssueName: (id: string, name: string) => ({ id, name }),
        updateIssueDescription: (id: string, description: string) => ({ id, description }),
        createIssueCohort: (id: string, name: string, description: string) => ({ id, name, description }),

        splitIssueSuccess: (newIssueIds: string[]) => ({ newIssueIds }),
        mutationSuccess: (mutationName: string) => ({ mutationName }),
        mutationFailure: (mutationName: string, error: unknown) => ({ mutationName, error }),
        clearNeedsReload: true,
    }),

    reducers({
        needsReload: [
            false,
            {
                mutationSuccess: () => true,
                clearNeedsReload: () => false,
            },
        ],
    }),

    listeners(({ actions }) => {
        async function runMutation(
            mutationName: string,
            cb: () => Promise<void>,
            onSuccess?: () => Promise<void>
        ): Promise<void> {
            try {
                await cb()
                if (onSuccess) {
                    await onSuccess()
                }
                actions.mutationSuccess(mutationName)
            } catch (e: unknown) {
                actions.mutationFailure(mutationName, e)
            }
        }
        return {
            mergeIssues: async ({ ids }) => {
                const [firstId, ...otherIds] = ids
                if (firstId && otherIds.length > 0) {
                    await runMutation(
                        'mergeIssues',
                        async () => {
                            posthog.capture('error_tracking_issue_merged', { primary: firstId })
                            await errorTrackingIssuesMergeCreate(String(ApiConfig.getCurrentProjectId()), firstId, {
                                ids: otherIds,
                            })
                        },
                        async () => pendingUpdateActions()?.captureMergePendingUpdates(firstId, otherIds)
                    )
                }
            },
            splitIssue: async ({ id, fingerprints }) => {
                await runMutation('splitIssues', async () => {
                    posthog.capture('error_tracking_issue_split', { issueId: id })
                    const response = await errorTrackingIssuesSplitCreate(String(ApiConfig.getCurrentProjectId()), id, {
                        fingerprints: fingerprints,
                    })
                    actions.splitIssueSuccess(response.new_issue_ids)
                })
            },
            resolveIssues: async ({ ids }) => {
                await runMutation(
                    'resolveIssues',
                    async () => {
                        posthog.capture('error_tracking_issue_bulk_resolve')
                        await errorTrackingIssuesBulkCreate(String(ApiConfig.getCurrentProjectId()), {
                            action: 'set_status',
                            ids: ids,
                            status: 'resolved',
                        })
                    },
                    async () => pendingUpdateActions()?.capturePendingUpdatesForIssues(ids, { status: 'resolved' })
                )

                globalSetupLogic.findMounted()?.actions.markTaskAsCompleted(SetupTaskId.ResolveFirstError)
            },
            suppressIssues: async ({ ids }) => {
                await runMutation(
                    'suppressIssues',
                    async () => {
                        posthog.capture('error_tracking_issue_bulk_suppress')
                        await errorTrackingIssuesBulkCreate(String(ApiConfig.getCurrentProjectId()), {
                            action: 'set_status',
                            ids: ids,
                            status: 'suppressed',
                        })
                    },
                    async () => pendingUpdateActions()?.capturePendingUpdatesForIssues(ids, { status: 'suppressed' })
                )
            },
            activateIssues: async ({ ids }) => {
                await runMutation(
                    'activateIssues',
                    async () => {
                        posthog.capture('error_tracking_issue_bulk_activate')
                        await errorTrackingIssuesBulkCreate(String(ApiConfig.getCurrentProjectId()), {
                            action: 'set_status',
                            ids: ids,
                            status: 'active',
                        })
                    },
                    async () => pendingUpdateActions()?.capturePendingUpdatesForIssues(ids, { status: 'active' })
                )
            },
            assignIssues: async ({ ids, assignee }) => {
                await runMutation(
                    'assignIssues',
                    async () => {
                        posthog.capture('error_tracking_issue_bulk_assign')
                        await errorTrackingIssuesBulkCreate(String(ApiConfig.getCurrentProjectId()), {
                            action: 'assign',
                            ids: ids,
                            assignee: assignee,
                        })
                    },
                    async () => pendingUpdateActions()?.capturePendingUpdatesForIssues(ids, { assignee })
                )
            },
            updateIssueAssignee: async ({ id, assignee }) => {
                await runMutation(
                    'updateIssueAssignee',
                    async () => {
                        posthog.capture('error_tracking_issue_update_assignee')
                        await errorTrackingIssuesAssignPartialUpdate(String(ApiConfig.getCurrentProjectId()), id, {
                            assignee: assignee,
                        })
                    },
                    async () => pendingUpdateActions()?.capturePendingUpdatesForIssues([id], { assignee })
                )
            },
            updateIssueStatus: async ({ id, status }) => {
                if (!isWritableIssueStatus(status)) {
                    throw new Error(`Unsupported issue status: ${status}`)
                }
                await runMutation(
                    'updateIssueStatus',
                    async () => {
                        posthog.capture('error_tracking_issue_update_status', {
                            status,
                            issue_id: id,
                            source: 'issue_actions',
                        })
                        await errorTrackingIssuesPartialUpdate(String(ApiConfig.getCurrentProjectId()), id, { status })
                    },
                    async () => pendingUpdateActions()?.capturePendingUpdatesForIssues([id], { status })
                )
            },
            updateIssueName: async ({ id, name }) => {
                await runMutation(
                    'updateIssueName',
                    async () => {
                        posthog.capture('error_tracking_issue_update_name')
                        await errorTrackingIssuesPartialUpdate(String(ApiConfig.getCurrentProjectId()), id, { name })
                    },
                    async () => pendingUpdateActions()?.capturePendingUpdatesForIssues([id], { name })
                )
            },
            updateIssueDescription: async ({ id, description }) => {
                await runMutation(
                    'updateIssueDescription',
                    async () => {
                        posthog.capture('error_tracking_issue_update_description')
                        await errorTrackingIssuesPartialUpdate(String(ApiConfig.getCurrentProjectId()), id, {
                            description,
                        })
                    },
                    async () => pendingUpdateActions()?.capturePendingUpdatesForIssues([id], { description })
                )
            },
            createIssueCohort: async ({ id, name, description }) => {
                await runMutation('createIssueCohort', async () => {
                    let cohortParams = createCohortParams(name, description, id)
                    let formData = createCohortFormData(cohortParams)
                    // nosemgrep: prefer-codegen-api
                    let cohort = await api.cohorts.create(formData as Partial<CohortType>)
                    if (cohort.id === 'new') {
                        throw new Error('The created cohort does not have a persisted ID')
                    }
                    posthog.capture('error_tracking_issue_create_cohort', {
                        issueId: id,
                        cohortId: cohort.id,
                    })
                    await errorTrackingIssuesCohortUpdate(String(ApiConfig.getCurrentProjectId()), id, {
                        cohortId: cohort.id,
                    })
                })
            },
            mutationSuccess: ({ mutationName }) => {
                if (mutationName === 'updateIssueAssignee' || mutationName === 'assignIssues') {
                    tryShowMCPHint('error_tracking.assign')
                }
            },
        }
    }),
])

function createCohortParams(name: string, description: string, issueId: string): CohortType {
    return {
        id: 'new',
        name,
        description,
        groups: [],
        filters: {
            properties: {
                type: FilterLogicalOperator.Or,
                values: [
                    {
                        type: FilterLogicalOperator.Or,
                        values: [
                            {
                                key: '$exception',
                                type: BehavioralFilterKey.Behavioral,
                                value: BehavioralEventType.PerformEvent,
                                negation: false,
                                event_type: TaxonomicFilterGroupType.Events,
                                event_filters: [
                                    {
                                        key: `issue_id = ${escapeHogQLString(issueId)}`,
                                        type: PropertyFilterType.HogQL,
                                    },
                                ],
                                explicit_datetime: '-30d',
                            },
                        ],
                    },
                ],
            },
        },
    }
}
