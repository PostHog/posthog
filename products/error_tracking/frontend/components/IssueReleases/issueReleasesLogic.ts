export const issueReleasesLogic = kea<issueReleasesLogicType>([
    props({} as IssueReleasesLogicProps),
    key(({ issueId }: IssueReleasesLogicProps) => issueId),
    path((key) => ['products', 'error_tracking', 'components', 'IssueReleases', 'issueReleasesLogic', key]),
    connect(() => ({
        values: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['dateRange', 'filterGroup', 'filterTestAccounts'],
            issueFilterPreviewLogic,
            ['releasesViewMode'],
        ],
        actions: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['addPropertyFilter', 'setDateRange', 'setFilterGroup', 'setFilterTestAccounts'],
        ],
    })),
    actions({
        loadReleases: true,
        selectNamespace: (namespace: string | null) => ({ namespace }),
    }),
    loaders(({ props, values }) => ({
        releases: [
            null as IssueReleasesResult | null,
            {
                loadReleases: async (_: { value: true }, breakpoint) => {
                    await breakpoint(100)
                    // Read connected values before the request because the filters logic may unmount while it runs.
                    const { dateRange, filterGroup, filterTestAccounts } = values
                    const bucketing = computeReleaseBucketing(dateRange)
                    if (!bucketing) {
                        return null
                    }
                    const response = (await api.query(
                        errorTrackingIssueReleasesQuery({
                            issueId: props.issueId,
                            dateRange,
                            filterGroup,
                            filterTestAccounts,
                            bucketSeconds: bucketing.bucketSeconds,
                        }),
                        { refresh: 'blocking' }
                    )) as HogQLQueryResponse
                    breakpoint()
                    return { bucketing, rows: (response.results ?? []) as IssueReleasesQueryRow[] }
                },
            },
        ],
    })),
    reducers({
        selectedNamespace: [
            null as string | null,
            {
                selectNamespace: (_, { namespace }) => namespace,
            },
        ],
        releasesError: [
            null as string | null,
            {
                loadReleases: () => null,
                loadReleasesSuccess: () => null,
                loadReleasesFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        timeline: [
            (s) => [s.releases, s.releasesViewMode, s.selectedNamespace],
            (
                releases: IssueReleasesResult | null,
                releasesViewMode: IssueReleasesViewMode,
                selectedNamespace: string | null
            ): IssueReleaseTimeline | null => {
                if (!releases) {
                    return null
                }
                const maxVisible = releasesViewMode === 'stacked' ? MAX_STACKED_RELEASES : MAX_VISIBLE_RELEASES
                const unfiltered = buildIssueReleaseTimeline(releases.rows, releases.bucketing, maxVisible)
                // A namespace that left the range after a refetch falls back to every app.
                if (selectedNamespace === null || !unfiltered.namespaces.includes(selectedNamespace)) {
                    return unfiltered
                }
                return buildIssueReleaseTimeline(releases.rows, releases.bucketing, maxVisible, selectedNamespace)
            },
        ],
    }),
    listeners(({ actions }) => ({
        addPropertyFilter: () => actions.loadReleases(),
        setDateRange: () => actions.loadReleases(),
        setFilterGroup: () => actions.loadReleases(),
        setFilterTestAccounts: () => actions.loadReleases(),
    })),
    afterMount(({ actions }) => {
        actions.loadReleases()
    }),
])
