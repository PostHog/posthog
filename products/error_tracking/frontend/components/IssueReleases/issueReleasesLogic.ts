export const issueReleasesLogic = kea<issueReleasesLogicType>([
    props({} as IssueReleasesLogicProps),
    key(({ issueId }: IssueReleasesLogicProps) => issueId),
    path((key) => ['products', 'error_tracking', 'components', 'IssueReleases', 'issueReleasesLogic', key]),
    connect(() => ({
        values: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['dateRange', 'filterGroup', 'filterTestAccounts'],
            issueFilterPreviewLogic,
            ['releasesViewMode'],
        ],
        actions: [
            issueFiltersLogic({ logicKey: ERROR_TRACKING_ISSUE_SCENE_LOGIC_KEY }),
            ['addPropertyFilter', 'setDateRange', 'setFilterGroup', 'setFilterTestAccounts'],
            issueFilterPreviewLogic,
            ['setReleasesViewMode', 'applyPropertyFilters', 'clearPropertyFilter'],
        ],
    })),
    actions({
        loadReleases: true,
        selectNamespace: (namespace: string | null) => ({ namespace }),
        selectStrip: (strip: IssueReleaseStrip) => ({ strip }),
    }),
    loaders(({ props, values }) => ({
        releases: [
            null as ErrorTrackingReleasesQueryResponse | null,
            {
                loadReleases: async (_: { value: true }, breakpoint) => {
                    await breakpoint(100)
                    // Read connected values before the request because the filters logic may unmount while it runs.
                    const { dateRange, filterGroup, filterTestAccounts, releasesViewMode } = values
                    const stacked = releasesViewMode === 'stacked'
                    const response = (await api.query(
                        errorTrackingReleasesQuery({
                            issueId: props.issueId,
                            dateRange,
                            filterGroup,
                            filterTestAccounts,
                            maxReleases: stacked ? MAX_STACKED_RELEASES : MAX_VISIBLE_RELEASES,
                            orderBy: stacked ? 'occurrences' : 'latest',
                        }),
                        { refresh: 'blocking' }
                    )) as ErrorTrackingReleasesQueryResponse
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers({
        releasesError: [
            null as string | null,
            {
                loadReleases: () => null,
                loadReleasesSuccess: () => null,
                loadReleasesFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        // The `$app_namespace` chip is the only source of truth, so the picker and the chip never disagree.
        selectedNamespace: [
            (s) => [s.filterGroup],
            (filterGroup: UniversalFiltersGroup): string | null => selectedAppNamespace(filterGroup),
        ],
    }),
    listeners(({ actions }) => ({
        selectStrip: ({ strip }) => {
            const filters = releasePropertyFilters(strip)
            if (filters.length > 0) {
                actions.applyPropertyFilters(filters)
            }
        },
        selectNamespace: ({ namespace }) => {
            if (namespace) {
                actions.applyPropertyFilters([
                    { key: '$app_namespace', value: namespace, operator: PropertyOperator.Exact },
                ])
            } else {
                actions.clearPropertyFilter('$app_namespace')
            }
        },
        addPropertyFilter: () => actions.loadReleases(),
        setDateRange: () => actions.loadReleases(),
        setFilterGroup: () => actions.loadReleases(),
        setFilterTestAccounts: () => actions.loadReleases(),
        setReleasesViewMode: () => actions.loadReleases(),
    })),
    afterMount(({ actions }) => {
        actions.loadReleases()
    }),
])
