export const biSceneLogic: LogicWrapper<biSceneLogicType> = kea<biSceneLogicType>([
    props({} as BISceneLogicProps),
    key((props) => props.tabId),
    path((key) => ['products', 'business_intelligence', 'biSceneLogic', key]),
    connect((props: BISceneLogicProps) => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            biEditorLogic(props),
            ['config', 'generatedQuery', 'autoUpdate'],
            databaseTableListLogic,
            ['connectionId'],
            connectionSelectorLogic,
            ['connectionOptions', 'connectionOptionsLoading'],
        ],
        actions: [biEditorLogic(props), ['restoreState', 'runAfterChange', 'resetConfig', 'setChartType']],
    })),
    actions({
        restoreWorksheet: (worksheet: BIVisualizationNode) => ({ worksheet }),
        setVisualization: (visualization: VisualizationNode) => ({ visualization }),
        setName: (name: string) => ({ name }),
        runQuery: true,
        cancelQuery: true,
        setLastRunQuery: (query: BIVisualizationNode | null) => ({ query }),
        discardChanges: true,
        shareWorksheet: true,
        syncWorksheetUrl: true,
        openWorksheet: true,
        clearInsight: true,
        selectConnection: (connectionId: string | null) => ({ connectionId }),
        setExportViewName: (name: string) => ({ name }),
        setExportViewOpen: (open: boolean) => ({ open }),
    }),
    loaders(({ values, actions }) => ({
        insight: [
            null as InsightApi | null,
            {
                loadInsight: async (shortId: string, breakpoint) => {
                    const response = await insightsList(String(values.currentTeamId), {
                        short_id: shortId,
                        basic: true,
                    })
                    breakpoint()
                    const insight = response.results[0]
                    if (!insight || !isBIVisualizationNode(insight.query)) {
                        throw new Error('This insight is not a BI worksheet.')
                    }
                    return insight
                },
                saveInsight: async () => {
                    if (values.saveDisabledReason) {
                        return values.insight
                    }
                    const dashboard = Number(router.values.searchParams.dashboard)
                    const payload = {
                        name: values.name.trim(),
                        query: JSON.parse(JSON.stringify(values.worksheet)) as BIVisualizationNodeApi,
                        saved: true,
                        ...(!values.insight && Number.isInteger(dashboard) && dashboard > 0
                            ? { dashboards: [dashboard] }
                            : {}),
                    }
                    const state = { editorView: BIEditorView.BI, config: values.config }
                    const operation = values.insight ? 'update' : 'create'
                    const insight = values.insight
                        ? await insightsPartialUpdate(String(values.currentTeamId), values.insight.id, payload)
                        : await insightsCreate(String(values.currentTeamId), payload)
                    captureBIEditorQuerySaved(state, 'insight', operation, !!payload.dashboards?.length)
                    captureBIWorksheetAction('saved', state.config, { insight_id: insight.id })
                    if (payload.dashboards?.length) {
                        captureBIWorksheetAction('added_to_dashboard', state.config, { insight_id: insight.id })
                    }
                    return insight
                },
            },
        ],
        exportedView: [
            null as Awaited<ReturnType<typeof warehouseSavedQueriesCreate>> | null,
            {
                exportView: async () => {
                    if (!values.generatedQuery || !values.exportViewName.trim()) {
                        return null
                    }
                    const view = await warehouseSavedQueriesCreate(String(values.currentTeamId), {
                        name: values.exportViewName.trim(),
                        query: values.worksheet.source,
                    })
                    captureBIEditorQuerySaved({ editorView: BIEditorView.BI, config: values.config }, 'view', 'create')
                    actions.setExportViewOpen(false)
                    lemonToast.success('SQL view created. Save the worksheet as an insight to keep its shelves.')
                    return view
                },
            },
        ],
    })),
    reducers({
        visualization: [
            emptyWorksheet(),
            {
                restoreWorksheet: (_, { worksheet }) => worksheet,
                setVisualization: (state, { visualization }) => ({
                    ...state,
                    ...visualization,
                    kind: NodeKind.BIVisualizationNode,
                }),
            },
        ],
        insight: { clearInsight: () => null },
        name: ['Untitled worksheet', { setName: (_, { name }) => name }],
        lastRunQuery: [null as BIVisualizationNode | null, { setLastRunQuery: (_, { query }) => query }],
        loadError: [
            null as string | null,
            { loadInsight: () => null, loadInsightFailure: (_, { error }) => error, loadInsightSuccess: () => null },
        ],
        exportViewName: ['', { setExportViewName: (_, { name }) => name }],
        exportViewOpen: [false, { setExportViewOpen: (_, { open }) => open }],
    }),
    selectors({
        dataNodeKey: [(_, props) => [props.tabId], (tabId: string): string => `InsightViz.new-bi-${tabId}`],
        worksheet: [
            (s) => [s.config, s.generatedQuery, s.visualization],
            (
                config: BIConfig,
                generatedQuery: BIQueryBuildResult | null,
                visualization: BIVisualizationNode
            ): BIVisualizationNode => ({
                ...visualization,
                ...generatedQuery?.node,
                kind: NodeKind.BIVisualizationNode,
                config,
                display: config.chartType,
                source: generatedQuery
                    ? mergeBIQuerySource(visualization.source, generatedQuery.node.source)
                    : { ...visualization.source, query: '' },
                chartSettings: mergeBIChartSettings(visualization.chartSettings, generatedQuery?.node.chartSettings),
                tableSettings: mergeBITableSettings(visualization.tableSettings, generatedQuery?.node.tableSettings),
            }),
        ],
        hasUnsavedChanges: [
            (s) => [s.worksheet, s.name, s.insight],
            (worksheet: BIVisualizationNode, name: string, insight: InsightApi | null): boolean =>
                !equal(JSON.parse(JSON.stringify(worksheet)), insight?.query) || name !== insight?.name,
        ],
        saveDisabledReason: [
            (s) => [s.generatedQuery, s.insight, s.name],
            (
                generatedQuery: BIQueryBuildResult | null,
                insight: InsightApi | null,
                name: string
            ): string | undefined => {
                if (!generatedQuery) {
                    return 'Select a table and resolve any invalid fields before saving'
                }
                if (!name.trim()) {
                    return 'Enter a worksheet name'
                }
                if (
                    insight &&
                    !accessLevelSatisfied(
                        AccessControlResourceType.Insight,
                        toAccessControlLevel(insight.user_access_level),
                        AccessControlLevel.Editor
                    )
                ) {
                    return 'You do not have permission to edit this insight'
                }
            },
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        [dataNodeLogic({ key: `InsightViz.new-bi-${props.tabId}`, query: emptyWorksheet().source }).actionTypes
            .loadDataSuccess]: ({ response }) => {
            if (
                !cache.firstChartCaptured &&
                values.lastRunQuery &&
                response &&
                'results' in response &&
                Array.isArray(response.results) &&
                response.results.length
            ) {
                cache.firstChartCaptured = true
                captureBIWorksheetAction('first_chart', values.lastRunQuery.config, {
                    insight_id: values.insight?.id,
                    result_count: response.results.length,
                })
            }
        },
        resetConfig: () => {
            actions.restoreWorksheet({
                ...emptyWorksheet(),
                source: { kind: NodeKind.HogQLQuery, query: '', connectionId: values.connectionId ?? undefined },
            })
            actions.syncWorksheetUrl()
        },
        selectConnection: ({ connectionId }) => {
            if (connectionId !== values.connectionId) {
                actions.restoreWorksheet({
                    ...emptyWorksheet(),
                    source: { kind: NodeKind.HogQLQuery, query: '', connectionId: connectionId ?? undefined },
                })
                actions.syncWorksheetUrl()
            }
        },
        restoreWorksheet: ({ worksheet }) => {
            const connectionId = worksheet.source.connectionId ?? null
            claimConnectionScope(`bi:${props.tabId}`, connectionId)
            const connectionChanged = connectionId !== values.connectionId
            if (connectionChanged) {
                databaseTableListLogic.actions.setConnection(connectionId)
            }
            actions.restoreState({
                editorView: BIEditorView.BI,
                config: applyBIDateRange(worksheet.config, worksheet.source.filters?.dateRange),
            })
            if (connectionChanged || !databaseTableListLogic.values.database) {
                databaseTableListLogic.actions.loadDatabase({ shallow: true })
            }
            actions.setLastRunQuery(worksheet.source.query ? worksheet : null)
        },
        loadInsightSuccess: ({ insight }) => {
            if (insight && isBIVisualizationNode(insight.query)) {
                actions.setName(insight.name || 'Untitled worksheet')
                let worksheet: BIVisualizationNode = insight.query
                const { q, filters } = router.values.hashParams
                if (q) {
                    try {
                        const draft = typeof q === 'string' ? JSON.parse(q) : q
                        if (isBIVisualizationNode(draft) && parseBIEditorState(BIEditorView.BI, draft.config)) {
                            worksheet = draft
                        }
                    } catch {
                        lemonToast.error('Could not restore worksheet edits from the link.')
                    }
                }
                if (filters && typeof filters === 'object' && !Array.isArray(filters)) {
                    worksheet = { ...worksheet, source: { ...worksheet.source, filters: filters as HogQLFilters } }
                }
                actions.restoreWorksheet(worksheet)
                void insightsViewedCreate(String(values.currentTeamId), { insight_ids: [insight.id] }).catch(() => {})
            }
        },
        saveInsightSuccess: ({ insight }) => {
            if (insight) {
                localStorage.removeItem(`bi-worksheet-${values.currentTeamId}-${props.tabId}`)
                refreshTreeItem('insight', insight.short_id)
                const dashboard = router.values.searchParams.dashboard
                router.actions.push(
                    urls.businessIntelligenceWorksheet(insight.short_id),
                    dashboard ? { dashboard } : {}
                )
            }
        },
        runAfterChange: async (_, breakpoint) => {
            actions.syncWorksheetUrl()
            if (!values.generatedQuery) {
                const dataLogic = dataNodeLogic.findMounted({ key: values.dataNodeKey })
                dataLogic?.actions.cancelQuery()
                dataLogic?.actions.clearResponse()
                actions.setLastRunQuery(null)
                return
            }
            if (!values.autoUpdate) {
                return
            }
            await breakpoint(400)
            if (values.autoUpdate && values.generatedQuery) {
                const dataLogic = dataNodeLogic.findMounted({ key: values.dataNodeKey })
                if (
                    !equal(values.lastRunQuery?.source, values.worksheet.source) ||
                    (!dataLogic?.values.responseLoading &&
                        (!dataLogic?.values.response ||
                            dataLogic.values.responseError ||
                            dataLogic.values.queryCancelled))
                ) {
                    actions.runQuery()
                } else {
                    actions.setLastRunQuery(values.worksheet)
                }
            }
        },
        runQuery: () => {
            if (!values.generatedQuery) {
                return
            }
            captureBIEditorQueryRun({ editorView: BIEditorView.BI, config: values.config })
            const unchanged = equal(values.lastRunQuery?.source, values.worksheet.source)
            actions.setLastRunQuery(values.worksheet)
            if (unchanged) {
                dataNodeLogic.findMounted({ key: values.dataNodeKey })?.actions.loadData('force_async')
            }
        },
        cancelQuery: () => dataNodeLogic.findMounted({ key: values.dataNodeKey })?.actions.cancelQuery(),
        setVisualization: ({ visualization }) => {
            const config = applyBIDateRange(values.config, visualization.source.filters?.dateRange)
            if (config !== values.config) {
                actions.restoreState({ editorView: BIEditorView.BI, config })
            }
            if (visualization.display && visualization.display !== values.config.chartType) {
                actions.setChartType(visualization.display)
            }
            actions.setLastRunQuery(values.worksheet)
            actions.syncWorksheetUrl()
        },
        discardChanges: () => {
            if (isBIVisualizationNode(values.insight?.query)) {
                actions.restoreWorksheet(values.insight.query)
                actions.setName(values.insight.name || 'Untitled worksheet')
            } else {
                actions.restoreWorksheet(emptyWorksheet())
                actions.setName('Untitled worksheet')
            }
            actions.syncWorksheetUrl()
        },
        syncWorksheetUrl: () => {
            localStorage.setItem(
                `bi-worksheet-${values.currentTeamId}-${props.tabId}`,
                JSON.stringify(values.worksheet)
            )
            cache.lastHash = JSON.stringify(values.worksheet)
            router.actions.replace(
                values.insight
                    ? urls.businessIntelligenceWorksheet(values.insight.short_id)
                    : urls.businessIntelligenceNew(),
                router.values.searchParams,
                { q: cache.lastHash }
            )
        },
        shareWorksheet: async () => {
            actions.syncWorksheetUrl()
            await copyToClipboard(window.location.href, 'worksheet link')
        },
        openWorksheet: () => {
            const { searchParams, hashParams } = router.values
            const pathId = router.values.location.pathname.match(/\/bi\/([^/]+)$/)?.[1]
            const insightShortId =
                searchParams.open_insight || (pathId && pathId !== 'new' ? decodeURIComponent(pathId) : undefined)
            if (searchParams.open_view) {
                router.actions.replace(urls.sqlEditor({ view_id: searchParams.open_view }))
                return
            }
            if (insightShortId && cache.loadingId !== insightShortId) {
                cache.loadingId = insightShortId
                cache.firstChartCaptured = false
                actions.loadInsight(insightShortId)
                return
            }
            if (insightShortId) {
                return
            }
            if (cache.lastHash !== undefined && hashParams.q === cache.lastHash) {
                return
            }
            cache.loadingId = undefined
            actions.clearInsight()
            let worksheet = emptyWorksheet()
            try {
                const raw = hashParams.q ?? localStorage.getItem(`bi-worksheet-${values.currentTeamId}-${props.tabId}`)
                const parsed = raw && !hashParams.bi ? (typeof raw === 'string' ? JSON.parse(raw) : raw) : null
                if (isBIVisualizationNode(parsed) && parseBIEditorState(BIEditorView.BI, parsed.config)) {
                    worksheet = parsed
                } else {
                    const state = parseBIEditorState(BIEditorView.BI, hashParams.bi)
                    const built = state && buildBIQuery(state.config)
                    if (state) {
                        worksheet = {
                            ...worksheet,
                            ...built?.node,
                            kind: NodeKind.BIVisualizationNode,
                            config: state.config,
                        }
                    }
                }
            } catch {
                lemonToast.error('Could not restore the worksheet link.')
            }
            actions.restoreWorksheet(worksheet)
            actions.setName('Untitled worksheet')
        },
    })),
    urlToAction(({ actions }) => ({
        '/bi': () => actions.openWorksheet(),
        '/bi/new': () => actions.openWorksheet(),
        '/bi/:insightShortId': () => actions.openWorksheet(),
    })),
    beforeUnmount(({ props }) => {
        if (releaseConnectionScope(`bi:${props.tabId}`, databaseTableListLogic.values.connectionId)) {
            databaseTableListLogic.actions.resetConnectionScope()
        }
    }),
    afterMount(({ actions, values }) => {
        captureBIWorksheetAction('opened', values.config)
        connectionSelectorLogic.actions.maybeLoadConnectionOptions()
        actions.openWorksheet()
    }),
])
