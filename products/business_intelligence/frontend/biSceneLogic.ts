function emptyWorksheet(): BIVisualizationNode {
    return {
        kind: NodeKind.BIVisualizationNode,
        source: { kind: NodeKind.HogQLQuery, query: '' },
        config: { ...DEFAULT_BI_CONFIG, rows: [], columns: [], values: [], filters: [] },
        display: DEFAULT_BI_CONFIG.chartType,
    }
}

