export type biSourceContextLogicType = MakeLogicType<
    biSourceContextLogicValues,
    biSourceContextLogicActions,
    BISourceContextProps,
    biSourceContextLogicMeta
>

export const biSourceContextLogic = kea<biSourceContextLogicType>([
    props({} as BISourceContextProps),
    key(({ table }) => table.id + ':' + table.name),
    path((key) => ['products', 'business_intelligence', 'biSourceContextLogic', key]),
    connect((props: BISourceContextProps) => ({
        values: [databaseTableListLogic, ['database']],
        actions: [biSourceMetadataLogic(props), ['loadHealth']],
    })),
    loaders(({ props, values }) => ({
        description: [
            '',
            {
                loadDescription: async (): Promise<string> => {
                    const project = String(teamLogic.values.currentTeamId)
                    if (props.table.type === 'view' || props.table.type === 'materialized_view') {
                        return (await warehouseSavedQueriesRetrieve(project, props.table.id)).description ?? ''
                    }
                    return ''
                },
            },
        ],
        relationships: [
            null as { results: DataCatalogRelationshipProposalApi[]; hasMore: boolean } | null,
            {
                loadRelationships: async (): Promise<{
                    results: DataCatalogRelationshipProposalApi[]
                    hasMore: boolean
                }> => {
                    const existing = values.relationships?.results ?? []
                    const result = await dataCatalogRelationshipProposalsList(String(teamLogic.values.currentTeamId), {
                        table_name: props.table.name,
                        limit: 20,
                        offset: existing.length,
                    })
                    return { results: [...existing, ...result.results], hasMore: !!result.next }
                },
            },
        ],
    })),
    reducers({
        contextError: [
            false,
            {
                loadRelationships: () => false,
                loadRelationshipsFailure: () => true,
            },
        ],
    }),
    selectors({
        joins: [
            (s) => [s.database, (_, props) => props.table.name],
            (database: Required<DatabaseSchemaQueryResponse> | null, name) =>
                database?.joins?.filter(
                    (join) => join.source_table_name === name || join.joining_table_name === name
                ) ?? [],
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadDescription()
        actions.loadRelationships()
        actions.loadHealth()
    }),
])
