export type biPropertyFieldsLogicType = MakeLogicType<
    biPropertyFieldsLogicValues,
    biPropertyFieldsLogicActions,
    BIPropertyFieldsLogicProps,
    biPropertyFieldsLogicMeta
>

export const biPropertyFieldsLogic: LogicWrapper<biPropertyFieldsLogicType> = kea<biPropertyFieldsLogicType>([
    props({} as BIPropertyFieldsLogicProps),
    key(({ tabId, field }) => JSON.stringify([tabId, field.id])),
    path((key) => ['products', 'business_intelligence', 'frontend', 'biPropertyFieldsLogic', key]),
    connect({ values: [projectLogic, ['currentProjectId']] }),
    actions({ toggleExpanded: true, setSearch: (search: string) => ({ search }) }),
    loaders(({ props, values }) => ({
        page: [
            null as PaginatedEnterprisePropertyDefinitionListApi | null,
            {
                loadPage: async (
                    { offset }: { offset: number },
                    breakpoint
                ): Promise<PaginatedEnterprisePropertyDefinitionListApi | null> => {
                    const target = getBIPropertyTarget(props.field)
                    if (!target || !values.currentProjectId) {
                        return null
                    }
                    if (values.search) {
                        await breakpoint(250)
                    }
                    const response = await api.propertyDefinitionsList(String(values.currentProjectId), {
                        type: target.type,
                        group_type_index: target.groupTypeIndex,
                        exclude_hidden: true,
                        exclude_restricted: true,
                        search: values.search.trim() || undefined,
                        limit: 25,
                        offset,
                    })
                    breakpoint()
                    return {
                        ...response,
                        results: [...(offset ? (values.page?.results ?? []) : []), ...response.results],
                    }
                },
            },
        ],
    })),
    reducers({
        expanded: [false, { toggleExpanded: (expanded) => !expanded }],
        search: ['', { setSearch: (_, { search }) => search }],
        page: [null as PaginatedEnterprisePropertyDefinitionListApi | null, { setSearch: () => null }],
        error: [null as string | null, { loadPage: () => null, loadPageFailure: (_, { error }) => error }],
    }),
    selectors(({ props }) => ({
        fields: [
            (s) => [s.page],
            (page: PaginatedEnterprisePropertyDefinitionListApi | null): BIField[] =>
                buildBIPropertyFields(props.field, page?.results ?? []),
        ],
    })),
    listeners(({ actions, values }) => ({
        toggleExpanded: () => {
            if (values.expanded && !values.page && !values.pageLoading) {
                actions.loadPage({ offset: 0 })
            }
        },
        setSearch: () => actions.loadPage({ offset: 0 }),
    })),
])
