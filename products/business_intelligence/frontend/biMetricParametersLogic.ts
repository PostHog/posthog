export type biMetricParametersLogicType = MakeLogicType<
    biMetricParametersLogicValues,
    biMetricParametersLogicActions,
    biMetricParametersLogicProps,
    biMetricParametersLogicMeta
>

export const biMetricParametersLogic = kea<biMetricParametersLogicType>([
    path(['products', 'business_intelligence', 'frontend', 'biMetricParametersLogic']),
    props({} as { tabId: string }),
    key((props) => props.tabId),
    connect((props: { tabId: string }) => ({
        values: [biEditorLogic(props), ['config']],
        actions: [biEditorLogic(props), ['setSnapshotParameters']],
    })),
    actions({
        open: true,
        close: true,
        setDraft: (source: HogQLQuery, parameters: ParameterDraft[]) => ({ source, parameters }),
        changeParameter: (name: string, value: string | boolean) => ({ name, value }),
        apply: true,
    }),
    reducers({
        source: [null as HogQLQuery | null, { setDraft: (_, { source }) => source, close: () => null }],
        parameters: [
            [] as ParameterDraft[],
            {
                setDraft: (_, { parameters }) => parameters,
                changeParameter: (parameters, { name, value }) =>
                    parameters.map((parameter) => (parameter.name === name ? { ...parameter, value } : parameter)),
                close: () => [],
            },
        ],
    }),
    selectors({
        parameterErrors: [
            (s) => [s.parameters],
            (parameters: ParameterDraft[]): Record<string, string> =>
                Object.assign(
                    Object.create(null) as Record<string, string>,
                    Object.fromEntries(
                        parameters.flatMap(({ name, type, value }) =>
                            type === 'number' && (String(value).trim() === '' || !Number.isFinite(Number(value)))
                                ? [[name, 'Enter a valid number']]
                                : []
                        )
                    )
                ),
        ],
        applyDisabledReason: [
            (s) => [s.source, s.config, s.parameterErrors],
            (source: HogQLQuery | null, config: BIConfig, errors: Record<string, string>): string | undefined =>
                source !== config.querySnapshot
                    ? 'The worksheet changed. Close this dialog and try again.'
                    : Object.keys(errors).length
                      ? 'Fix the invalid parameters first'
                      : undefined,
        ],
    }),
    listeners(({ actions, values }) => ({
        open: () => {
            if (values.config.querySnapshot) {
                actions.setDraft(values.config.querySnapshot, metricParameterDrafts(values.config.querySnapshot))
            }
        },
        apply: () => {
            if (!values.source || values.applyDisabledReason) {
                return
            }
            actions.setSnapshotParameters(
                values.source,
                Object.fromEntries(
                    values.parameters.map(({ name, type, value }) => [name, type === 'number' ? Number(value) : value])
                )
            )
            actions.close()
        },
    })),
])
