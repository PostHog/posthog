import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'

import { HogQLQuery } from '~/queries/schema/schema-general'

import type { BIConfig } from '../../../frontend/src/queries/schema/schema-business-intelligence'
import { biEditorLogic } from './biEditorLogic'

type ParameterDraft = { name: string; type: 'string' | 'number' | 'boolean'; value: string | boolean }

export function metricParameterDrafts(query?: HogQLQuery): ParameterDraft[] {
    return Object.entries(query?.values ?? {}).flatMap<ParameterDraft>(([name, value]) => {
        if (typeof value === 'boolean') {
            return [{ name, type: 'boolean' as const, value }]
        }
        if (typeof value === 'string' || (typeof value === 'number' && Number.isFinite(value))) {
            return [{ name, type: typeof value as 'string' | 'number', value: String(value) }]
        }
        return []
    })
}

