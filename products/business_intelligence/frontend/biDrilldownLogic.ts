import { MakeLogicType, actions, kea, key, path, props, reducers, selectors, listeners } from 'kea'

import { VisualizationNode, NodeKind, DashboardFilter, HogQLVariable } from '~/queries/schema/schema-general'

import { createBIDashboardSelection } from './biDashboardCrossFilters'
import { BIDrillSelection, getBIDrillQueries, getBIDrillSelection, getBIEffectiveQuery } from './biDrilldown'
import { captureBIWorksheetAction } from './biEditorAnalytics'
import { getBIHierarchyDrills, BIHierarchyDrill } from './biHierarchies'

export interface BIDrilldownProps {
    key: string
    query: VisualizationNode
    filtersOverride?: DashboardFilter | null
    variablesOverride?: Record<string, HogQLVariable> | null
    onFilterDashboard?: (record: Record<string, unknown>) => void
    isDashboardFilterSelected?: (record: Record<string, unknown>) => boolean
    getDashboardFilterUrl?: (record: Record<string, unknown>) => string
}

export interface BIDrillInteraction {
    x: number
    y: number
    timestamp?: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface biDrilldownLogicValues {
    dashboardFilterDisabledReason: string | undefined
    hierarchyDrills: BIHierarchyDrill[]
    interaction: BIDrillInteraction | null
    queries: ReturnType<typeof getBIDrillQueries>
    query: VisualizationNode
    record: Record<string, unknown> | null
    selection: BIDrillSelection | null
    showRows: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface biDrilldownLogicActions {
    close: () => {
        value: true
    }
    filterDashboard: () => {
        value: true
    }
    inspect: (record: Record<string, unknown>) => {
        record: Record<string, unknown>
    }
    openSqlEditor: () => {
        value: true
    }
    setInteraction: (interaction: BIDrillInteraction) => {
        interaction: BIDrillInteraction
    }
    viewRows: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface biDrilldownLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        dashboardFilterDisabledReason: (
            record: Record<string, unknown> | null,
            query: VisualizationNode
        ) => string | undefined
        hierarchyDrills: (selection: BIDrillSelection | null, query: VisualizationNode) => BIHierarchyDrill[]
        query: (arg: any, arg2: any, arg3: any) => VisualizationNode
        selection: (record: Record<string, unknown> | null, query: VisualizationNode) => BIDrillSelection | null
        queries: (selection: BIDrillSelection | null, query: VisualizationNode) => ReturnType<typeof getBIDrillQueries>
    }
}

export type biDrilldownLogicType = MakeLogicType<
    biDrilldownLogicValues,
    biDrilldownLogicActions,
    BIDrilldownProps,
    biDrilldownLogicMeta
>

export const biDrilldownLogic = kea<biDrilldownLogicType>([
    props({} as BIDrilldownProps),
    key((props) => props.key),
    path((key) => ['products', 'business_intelligence', 'biDrilldownLogic', key]),
    actions({
        inspect: (record: Record<string, unknown>) => ({ record }),
        setInteraction: (interaction: BIDrillInteraction) => ({ interaction }),
        openSqlEditor: true,
        filterDashboard: true,
        close: true,
        viewRows: true,
    }),
    reducers({
        interaction: [
            null as BIDrillInteraction | null,
            { setInteraction: (_, { interaction }) => interaction, close: () => null },
        ],
        record: [
            null as Record<string, unknown> | null,
            {
                inspect: (_, { record }) => record,
                close: () => null,
            },
        ],
        showRows: [false, { inspect: () => false, viewRows: () => true, close: () => false }],
    }),
    selectors({
        dashboardFilterDisabledReason: [
            (s) => [s.record, s.query],
            (record: Record<string, unknown> | null, query: VisualizationNode): string | undefined =>
                record &&
                query.kind === NodeKind.BIVisualizationNode &&
                createBIDashboardSelection(0, '', query, record)
                    ? undefined
                    : 'Choose a dimension in the current period. Grand totals and Other cannot filter a dashboard.',
        ],
        hierarchyDrills: [
            (s) => [s.selection, s.query],
            (selection: BIDrillSelection | null, query: VisualizationNode): BIHierarchyDrill[] =>
                selection && query.kind === NodeKind.BIVisualizationNode ? getBIHierarchyDrills(query, selection) : [],
        ],
        query: [
            () => [
                (_, props) => props.query,
                (_, props) => props.filtersOverride,
                (_, props) => props.variablesOverride,
            ],
            (query, filters, variables): VisualizationNode => getBIEffectiveQuery(query, filters, variables),
        ],
        selection: [
            (s) => [s.record, s.query],
            (record: Record<string, unknown> | null, query: VisualizationNode): BIDrillSelection | null =>
                record && query.kind === NodeKind.BIVisualizationNode
                    ? getBIDrillSelection(query.config, record)
                    : null,
        ],
        queries: [
            (s) => [s.selection, s.query],
            (selection: BIDrillSelection | null, query: VisualizationNode): ReturnType<typeof getBIDrillQueries> =>
                selection ? getBIDrillQueries(query, selection) : null,
        ],
    }),
    listeners(({ values, actions, props }) => ({
        inspect: () => {
            if (values.query.kind === NodeKind.BIVisualizationNode && values.selection) {
                captureBIWorksheetAction('drilldown_opened', values.query.config, {
                    previous_period: values.selection.previous,
                })
            }
        },
        filterDashboard: () => {
            if (props.onFilterDashboard && values.record && !values.dashboardFilterDisabledReason) {
                props.onFilterDashboard(values.record)
                actions.close()
            }
        },
        openSqlEditor: () => {
            if (values.queries) {
                if (values.query.kind === NodeKind.BIVisualizationNode) {
                    captureBIWorksheetAction('drilldown_sql_opened', values.query.config)
                }
                actions.close()
            }
        },
        viewRows: () => {
            if (values.query.kind === NodeKind.BIVisualizationNode) {
                captureBIWorksheetAction('underlying_rows_viewed', values.query.config, {
                    previous_period: values.selection?.previous,
                })
            }
        },
    })),
])
