export type biDrilldownLogicType = MakeLogicType<
    biDrilldownLogicValues,
    biDrilldownLogicActions,
    BIDrilldownProps,
    biDrilldownLogicMeta
>

export const biDrilldownLogic = kea<biDrilldownLogicType>([
    props({} as BIDrilldownProps),
    key((props) => props.key),
    path((key) => ['products', 'business_intelligence', 'biDrilldownLogic', key]),
    actions({
        inspect: (record: Record<string, unknown>) => ({ record }),
        setInteraction: (interaction: BIDrillInteraction) => ({ interaction }),
        filterDashboard: true,
        openWorksheet: true,
        openSqlEditor: true,
        close: true,
        viewRows: true,
    }),
    reducers({
        interaction: [
            null as BIDrillInteraction | null,
            { setInteraction: (_, { interaction }) => interaction, close: () => null },
        ],
        record: [
            null as Record<string, unknown> | null,
            {
                inspect: (_, { record }) => record,
                setInteraction: () => null,
                close: () => null,
            },
        ],
        showRows: [false, { inspect: () => false, viewRows: () => true, close: () => false }],
    }),
    selectors({
        dashboardFilterDisabledReason: [
            (s) => [s.record, s.query],
            (record: Record<string, unknown> | null, query: VisualizationNode): string | undefined =>
                record &&
                query.kind === NodeKind.BIVisualizationNode &&
                createBIDashboardSelection(0, '', query, record)
                    ? undefined
                    : 'Choose a dimension in the current period. Totals and Other cannot filter a dashboard.',
        ],
        hierarchyDrills: [
            (s) => [s.selection, s.query],
            (selection: BIDrillSelection | null, query: VisualizationNode): BIHierarchyDrill[] =>
                selection && query.kind === NodeKind.BIVisualizationNode ? getBIHierarchyDrills(query, selection) : [],
        ],
        query: [
            () => [
                (_, props) => props.query,
                (_, props) => props.filtersOverride,
                (_, props) => props.variablesOverride,
            ],
            (query, filters, variables): VisualizationNode => getBIEffectiveQuery(query, filters, variables),
        ],
        selection: [
            (s) => [s.record, s.query],
            (record: Record<string, unknown> | null, query: VisualizationNode): BIDrillSelection | null =>
                record && query.kind === NodeKind.BIVisualizationNode
                    ? getBIDrillSelection(query.config, record)
                    : null,
        ],
        queries: [
            (s) => [s.selection, s.query],
            (selection: BIDrillSelection | null, query: VisualizationNode): ReturnType<typeof getBIDrillQueries> =>
                selection ? getBIDrillQueries(query, selection) : null,
        ],
    }),
    listeners(({ values, actions, props, cache }) => ({
        inspect: () => {
            if (props.dashboardFilterActive && props.onFilterDashboard && !values.dashboardFilterDisabledReason) {
                actions.filterDashboard()
                return
            }
            if ((props.dashboardMenu || props.onFilterDashboard) && values.interaction?.clickCount === 2) {
                if (props.onFilterDashboard && !values.dashboardFilterDisabledReason) {
                    actions.filterDashboard()
                } else {
                    actions.close()
                }
                return
            }
            if (props.dashboardMenu || props.onFilterDashboard) {
                cache.disposables.add(() => {
                    const interaction = values.interaction
                    const onClick = (event: MouseEvent): void => {
                        if (
                            interaction?.timestamp !== undefined &&
                            event.detail > 0 &&
                            event.button === 0 &&
                            !event.metaKey &&
                            !event.ctrlKey &&
                            !event.shiftKey &&
                            !event.altKey &&
                            event.timeStamp - interaction.timestamp >= 0 &&
                            event.timeStamp - interaction.timestamp <= 500 &&
                            Math.hypot(event.clientX - interaction.x, event.clientY - interaction.y) <= 6
                        ) {
                            event.preventDefault()
                            event.stopImmediatePropagation()
                            if (props.onFilterDashboard && !values.dashboardFilterDisabledReason) {
                                actions.filterDashboard()
                            } else {
                                actions.close()
                            }
                        }
                    }
                    const onScroll = (event: Event): void => {
                        if (
                            !(event.target instanceof Element && event.target.closest('[data-attr="bi-result-menu"]'))
                        ) {
                            actions.close()
                        }
                    }
                    window.addEventListener('scroll', onScroll, true)
                    window.addEventListener('resize', actions.close)
                    document.addEventListener('click', onClick, true)
                    return () => {
                        window.removeEventListener('scroll', onScroll, true)
                        window.removeEventListener('resize', actions.close)
                        document.removeEventListener('click', onClick, true)
                    }
                }, 'result-menu-position')
            }
            if (values.query.kind === NodeKind.BIVisualizationNode && values.selection) {
                captureBIWorksheetAction('drilldown_opened', values.query.config, {
                    previous_period: values.selection.previous,
                })
            }
        },
        filterDashboard: () => {
            if (props.onFilterDashboard && values.record && !values.dashboardFilterDisabledReason) {
                props.onFilterDashboard(values.record)
                actions.close()
            }
        },
        close: () => cache.disposables.dispose('result-menu-position'),
        openWorksheet: () => {
            if (values.queries?.worksheet) {
                if (values.query.kind === NodeKind.BIVisualizationNode) {
                    captureBIWorksheetAction('drilldown_worksheet_opened', values.query.config)
                }
                actions.close()
            }
        },
        openSqlEditor: () => {
            if (values.queries) {
                if (values.query.kind === NodeKind.BIVisualizationNode) {
                    captureBIWorksheetAction('drilldown_sql_opened', values.query.config)
                }
                actions.close()
            }
        },
        viewRows: () => {
            cache.disposables.dispose('result-menu-position')
            if (values.query.kind === NodeKind.BIVisualizationNode) {
                captureBIWorksheetAction('underlying_rows_viewed', values.query.config, {
                    previous_period: values.selection?.previous,
                })
            }
        },
    })),
])
