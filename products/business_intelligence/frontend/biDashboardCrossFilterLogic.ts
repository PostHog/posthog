export type biDashboardCrossFilterLogicType = MakeLogicType<
    biDashboardCrossFilterLogicValues,
    biDashboardCrossFilterLogicActions,
    BIDashboardCrossFilterProps,
    biDashboardCrossFilterLogicMeta
>

export const biDashboardCrossFilterLogic: LogicWrapper<biDashboardCrossFilterLogicType> =
    kea<biDashboardCrossFilterLogicType>([
        props({} as BIDashboardCrossFilterProps),
        key(({ dashboardId }) => dashboardId),
        path((key) => ['products', 'business_intelligence', 'biDashboardCrossFilterLogic', key]),
        actions({
            setEnabled: (enabled: boolean) => ({ enabled }),
            setSelection: (selection: BIDashboardSelection | null) => ({ selection }),
            selectMark: (
                tileId: number,
                title: string,
                query: BIVisualizationNode,
                record: Record<string, unknown>
            ) => ({ tileId, title, query, record }),
        }),
        reducers({
            enabled: [false, { setEnabled: (_, { enabled }) => enabled }],
            selection: [
                null as BIDashboardSelection | null,
                { setSelection: (_, { selection }) => selection, setEnabled: () => null },
            ],
        }),
        selectors({
            targets: [
                (s) => [s.selection, (_, props) => props.tiles],
                (selection: BIDashboardSelection | null, tiles: DashboardTile[] | undefined) =>
                    getBIDashboardTargets(tiles ?? [], selection),
            ],
        }),
        listeners(({ actions, values }) => ({
            selectMark: ({ tileId, title, query, record }) => {
                if (!values.enabled) {
                    return
                }
                const selection = createBIDashboardSelection(tileId, title, query, record)
                if (!selection) {
                    lemonToast.info(
                        'Choose a dimension value in the current period. Totals and Other are not supported.'
                    )
                    return
                }
                actions.setSelection(equal(values.selection, selection) ? null : selection)
                captureBIWorksheetAction('dashboard_segment_selected', query.config)
            },
        })),
        propsChanged(({ props, values, actions }, oldProps) => {
            if (values.selection && props.tiles && oldProps.tiles) {
                const source = props.tiles.find(({ id }) => id === values.selection!.tileId)
                const previous = oldProps.tiles.find(({ id }) => id === values.selection!.tileId)
                if (!source || !equal(source.insight?.query, previous?.insight?.query)) {
                    actions.setSelection(null)
                }
            }
        }),
    ])
