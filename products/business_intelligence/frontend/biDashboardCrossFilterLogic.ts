export interface BIDashboardCrossFilterProps {
    dashboardId: number
    tiles?: DashboardTile[]
    loadQueue?: TaskQueue
}

function refreshUpdatedTiles(
    props: BIDashboardCrossFilterProps,
    oldProps: BIDashboardCrossFilterProps,
    targets: Record<number, BIVisualizationNode>
): void {
    const previousTiles = new Map(oldProps.tiles?.map((tile) => [tile.id, tile]))
    for (const tile of props.tiles ?? []) {
        const target = targets[tile.id]
        const previous = previousTiles.get(tile.id)
        if (!target || !previous || tile.insight?.last_refresh === previous.insight?.last_refresh) {
            continue
        }
        const dataLogic = dataNodeLogic.findMounted({
            key: insightVizDataNodeKey({ dashboardItemId: getBIDashboardItemId(props.dashboardId, tile.id, true) }),
        })
        if (dataLogic && equal(dataLogic.props.query, getBIVisualizationSource(target))) {
            dataLogic.actions.loadData('force_blocking')
        }
    }
}

