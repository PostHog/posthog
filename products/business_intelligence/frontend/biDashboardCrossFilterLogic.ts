export const biDashboardCrossFilterLogic: LogicWrapper<biDashboardCrossFilterLogicType> =
    kea<biDashboardCrossFilterLogicType>([
        props({} as BIDashboardCrossFilterProps),
        key(({ dashboardId }) => dashboardId),
        path((key) => ['products', 'business_intelligence', 'biDashboardCrossFilterLogic', key]),
        actions({
            restoreFromUrl: true,
            setSelection: (selection: BIDashboardSelection | null) => ({ selection }),
            selectMark: (
                tileId: number,
                title: string,
                query: BIVisualizationNode,
                record: Record<string, unknown>
            ) => ({ tileId, title, query, record }),
        }),
        reducers({
            selection: [null as BIDashboardSelection | null, { setSelection: (_, { selection }) => selection }],
        }),
        selectors({
            loadQueue: [() => [(_, props) => props.loadQueue], (loadQueue: TaskQueue | undefined) => loadQueue],
            sourceInsightUrl: [
                (s) => [s.selection, (_, props) => props.tiles],
                (selection: BIDashboardSelection | null, tiles: DashboardTile[] | undefined): string | undefined => {
                    const insight = tiles?.find((tile) => tile.id === selection?.tileId)?.insight
                    return insight ? urls.insightView(insight.short_id) : undefined
                },
            ],
            targets: [
                (s) => [s.selection, (_, props) => props.tiles],
                (selection: BIDashboardSelection | null, tiles: DashboardTile[] | undefined) =>
                    getBIDashboardTargets(tiles ?? [], selection),
            ],
        }),
        listeners(({ actions, values, props, cache }) => ({
            restoreFromUrl: () => {
                const link = readBIDashboardFilterLink(router.values.currentLocation.hashParams.bi_filter)
                if (equal(link, cache.restoredFilterLink)) {
                    return
                }
                if (!link) {
                    if (cache.restoredFilterLink) {
                        actions.setSelection(null)
                    }
                    cache.restoredFilterLink = null
                    return
                }
                if (link.dashboardId !== props.dashboardId) {
                    return
                }
                const tile = props.tiles?.find(({ id }) => id === link.tileId)
                const query = tile?.insight?.query
                if (!tile || !isCrossFilterWorksheet(query)) {
                    return
                }
                cache.restoredFilterLink = link
                actions.setSelection(
                    createBIDashboardSelection(tile.id, tile.insight?.name || 'Untitled worksheet', query, link.record)
                )
            },
            setSelection: ({ selection }) => {
                if (
                    !selection &&
                    readBIDashboardFilterLink(router.values.currentLocation.hashParams.bi_filter)?.dashboardId ===
                        props.dashboardId
                ) {
                    const location = router.values.currentLocation
                    const hash = { ...location.hashParams }
                    delete hash.bi_filter
                    cache.restoredFilterLink = null
                    router.actions.replace(location.pathname, location.searchParams, hash)
                }
            },
            selectMark: ({ tileId, title, query, record }) => {
                const selection = createBIDashboardSelection(tileId, title, query, record)
                if (!selection) {
                    lemonToast.info(
                        'Choose a dimension value in the current period. Grand totals and Other are not supported.'
                    )
                    return
                }
                const next = equal(values.selection, selection) ? null : selection
                actions.setSelection(next)
                if (next) {
                    const location = router.values.currentLocation
                    const url = getBIDashboardFilterLink(
                        new URL(`${location.pathname}${location.search}${location.hash}`, window.location.origin).href,
                        props.dashboardId,
                        tileId,
                        query.config,
                        record
                    )
                    cache.restoredFilterLink = readBIDashboardFilterLink(
                        new URLSearchParams(url.split('#')[1]).get('bi_filter')
                    )
                    router.actions.replace(url)
                }
                captureBIWorksheetAction('dashboard_segment_selected', query.config)
            },
        })),
        afterMount(({ actions }) => actions.restoreFromUrl()),
        urlToAction(({ actions, props }) => ({
            '/dashboard/:id': ({ id }) => {
                if (Number(id) === props.dashboardId) {
                    actions.restoreFromUrl()
                }
            },
        })),
        propsChanged(({ props, values, actions }, oldProps) => {
            if (props.tiles === oldProps.tiles) {
                return
            }
            if (values.selection && props.tiles && oldProps.tiles) {
                const source = props.tiles.find(({ id }) => id === values.selection!.tileId)
                const previous = oldProps.tiles.find(({ id }) => id === values.selection!.tileId)
                if (
                    !source ||
                    !equal(
                        getBIDashboardSelectionScope(source.insight?.query),
                        getBIDashboardSelectionScope(previous?.insight?.query)
                    )
                ) {
                    actions.setSelection(null)
                }
            }
            refreshUpdatedTiles(props, oldProps, values.targets)
            actions.restoreFromUrl()
        }),
    ])
