export const biFilterValuesLogic = kea<biFilterValuesLogicType>([
    props({} as BIFilterValuesLogicProps),
    key((props) => JSON.stringify(props.query)),
    path((key) => ['products', 'business_intelligence', 'frontend', 'biFilterValuesLogic', key]),
    actions({ setSearch: (search: string) => ({ search }), loadMore: true }),
    loaders(({ props, values, cache }) => ({
        page: [
            null as BIFilterValuePage | null,
            {
                loadOptions: async (
                    payload: { append?: boolean; debounce?: boolean } = {},
                    breakpoint
                ): Promise<BIFilterValuePage> => {
                    const { append = false, debounce = false } = payload
                    cache.disposables.dispose('valueQuery')
                    const search = values.search
                    const existing = append && values.page?.search === search ? values.page.values : []
                    if (debounce && !append && values.page?.search === search) {
                        return values.page
                    }
                    if (debounce) {
                        await breakpoint(300)
                    }
                    if (!props.query) {
                        return { search, values: [], hasMore: false }
                    }
                    const controller = new AbortController()
                    const queryId = uuid()
                    let settled = false
                    cache.disposables.add(
                        () => () => {
                            if (!settled) {
                                controller.abort()
                                void api.cancelQuery(queryId).catch((error) => {
                                    console.warn('Failed cancelling BI value query', error)
                                })
                            }
                        },
                        'valueQuery',
                        { pauseOnPageHidden: false }
                    )
                    const response = await performQuery(
                        searchBIFilterValues(props.query, search, existing.length),
                        { signal: controller.signal },
                        undefined,
                        queryId
                    )
                        .catch((error) => {
                            breakpoint()
                            throw error
                        })
                        .finally(() => {
                            settled = true
                        })
                    breakpoint()
                    if (props.config && (debounce || append)) {
                        captureBIWorksheetAction(
                            debounce ? 'filter_values_searched' : 'filter_values_page_loaded',
                            props.config,
                            {
                                result_count: Math.min(response.results.length, PAGE_SIZE),
                            }
                        )
                    }
                    return {
                        search,
                        values: [...existing, ...response.results.slice(0, PAGE_SIZE).map((row) => String(row[0]))],
                        hasMore: response.results.length > PAGE_SIZE,
                    }
                },
            },
        ],
    })),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        optionsError: [
            null as string | null,
            {
                loadOptions: () => null,
                loadOptionsSuccess: () => null,
                loadOptionsFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        options: [(s) => [s.page], (page: BIFilterValuePage | null): string[] | null => page?.values ?? null],
        hasMore: [(s) => [s.page], (page: BIFilterValuePage | null): boolean => page?.hasMore ?? false],
        optionsLoading: [(s) => [s.pageLoading], (loading: boolean): boolean => loading],
    }),
    listeners(({ actions, values }) => ({
        setSearch: () => actions.loadOptions({ debounce: true }),
        loadMore: () => {
            if (values.hasMore && !values.optionsLoading) {
                actions.loadOptions({ append: true })
            }
        },
    })),
    afterMount(({ actions, props }) => {
        if (props.active) {
            actions.loadOptions()
        }
    }),
    propsChanged(({ actions, values, props }) => {
        if (props.active && values.options === null && !values.optionsLoading && !values.optionsError) {
            actions.loadOptions()
        }
    }),
])
