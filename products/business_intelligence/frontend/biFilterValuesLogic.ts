import { captureBIWorksheetAction } from './biEditorAnalytics'

const PAGE_SIZE = 100

export function searchBIFilterValues(query: HogQLQuery, search: string, offset: number): HogQLQuery {
    return {
        ...query,
        query: `SELECT value FROM (${query.query}) AS bi_filter_values WHERE positionCaseInsensitiveUTF8(value, ${escapeHogQLString(search)}) > 0 ORDER BY value ASC LIMIT ${PAGE_SIZE + 1} OFFSET ${offset}`,
    }
}

