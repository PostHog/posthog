import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { projectLogic } from 'scenes/projectLogic'
import { urls } from 'scenes/urls'

import { FunnelsQuery, InsightVizNode, NodeKind } from '~/queries/schema/schema-general'
import type { Breadcrumb } from '~/types'

import { userJourneysDestroy, userJourneysFunnelQueryRetrieve, userJourneysRetrieve } from './generated/api'
import type { JourneyApi } from './generated/api.schemas'
import { JourneyLoadError, journeysBreadcrumb, toJourneyLoadError } from './journeySteps'
import { captureJourneyDeleted, captureJourneyViewed } from './userJourneyEvents'
import { userJourneysLogic } from './userJourneysLogic'

export interface UserJourneyLogicProps {
    id: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userJourneyLogicValues {
    currentProjectId: number | null // projectLogic
    breadcrumbs: Breadcrumb[]
    deleting: boolean
    funnelQuery: FunnelsQuery | null
    funnelQueryLoadFailed: boolean
    funnelQueryLoading: boolean
    insightQuery: InsightVizNode<FunnelsQuery> | null
    insightQueryOverride: InsightVizNode<FunnelsQuery> | null
    journey: JourneyApi | null
    journeyLoadError: JourneyLoadError | null
    journeyLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userJourneyLogicActions {
    deleteJourney: () => {
        value: true
    }
    deleteJourneyFinished: () => {
        value: true
    }
    loadFunnelQuery: () => any
    loadFunnelQueryFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFunnelQuerySuccess: (
        funnelQuery: FunnelsQuery,
        payload?: any
    ) => {
        funnelQuery: FunnelsQuery
        payload?: any
    }
    loadJourney: () => any
    loadJourneyFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadJourneySuccess: (
        journey: JourneyApi,
        payload?: any
    ) => {
        journey: JourneyApi
        payload?: any
    }
    setInsightQuery: (query: InsightVizNode<FunnelsQuery>) => {
        query: InsightVizNode<FunnelsQuery>
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userJourneyLogicMeta {
    key: any
}

export type userJourneyLogicType = MakeLogicType<
    userJourneyLogicValues,
    userJourneyLogicActions,
    UserJourneyLogicProps,
    userJourneyLogicMeta
>

export const userJourneyLogic = kea<userJourneyLogicType>([
    props({} as UserJourneyLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'user_journeys', 'frontend', 'userJourneyLogic', key]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        deleteJourney: true,
        deleteJourneyFinished: true,
        setInsightQuery: (query: InsightVizNode<FunnelsQuery>) => ({ query }),
    }),
    loaders(({ props, values }) => ({
        journey: [
            null as JourneyApi | null,
            {
                loadJourney: async () => userJourneysRetrieve(String(values.currentProjectId), props.id),
            },
        ],
        funnelQuery: [
            null as FunnelsQuery | null,
            {
                loadFunnelQuery: async () => {
                    const response = await userJourneysFunnelQueryRetrieve(String(values.currentProjectId), props.id)
                    // The generated type and the frontend query schema both come from the same Pydantic model, but
                    // they are separate TypeScript declarations, so the cast joins them at this one boundary.
                    return response.query as unknown as FunnelsQuery
                },
            },
        ],
    })),
    reducers({
        journeyLoadError: [
            null as JourneyLoadError | null,
            {
                loadJourney: () => null,
                loadJourneyFailure: (_, { errorObject }) => toJourneyLoadError(errorObject),
            },
        ],
        funnelQueryLoadFailed: [
            false,
            {
                loadFunnelQuery: () => false,
                loadFunnelQueryFailure: () => true,
            },
        ],
        insightQueryOverride: [
            null as InsightVizNode<FunnelsQuery> | null,
            {
                setInsightQuery: (_, { query }) => query,
                loadFunnelQuerySuccess: () => null,
            },
        ],
        deleting: [
            false,
            {
                deleteJourney: () => true,
                deleteJourneyFinished: () => false,
            },
        ],
    }),
    selectors({
        insightQuery: [
            (s) => [s.funnelQuery, s.insightQueryOverride],
            (
                funnelQuery: FunnelsQuery | null,
                insightQueryOverride: InsightVizNode<FunnelsQuery> | null
            ): InsightVizNode<FunnelsQuery> | null =>
                insightQueryOverride ??
                (funnelQuery
                    ? {
                          kind: NodeKind.InsightVizNode,
                          source: funnelQuery,
                          showHeader: true,
                          showTable: false,
                          showFilters: false,
                          embedded: true,
                      }
                    : null),
        ],
        breadcrumbs: [
            (s) => [s.journey, (_, p) => p.id],
            (journey: JourneyApi | null, id: string): Breadcrumb[] => [
                journeysBreadcrumb(),
                { key: ['UserJourney', id], name: journey?.name ?? 'Journey', iconType: 'insight/paths' },
            ],
        ],
    }),
    listeners(({ actions, values, props }) => ({
        loadJourneySuccess: ({ journey }) => {
            if (journey) {
                captureJourneyViewed(journey.steps.length, journey.source)
            }
        },
        deleteJourney: async () => {
            try {
                await userJourneysDestroy(String(values.currentProjectId), props.id)
                captureJourneyDeleted('detail')
                lemonToast.success('Journey deleted')
                userJourneysLogic.findMounted()?.actions.loadJourneys()
                router.actions.push(urls.userJourneys())
            } catch {
                lemonToast.error("Couldn't delete the journey. Try again.")
            } finally {
                actions.deleteJourneyFinished()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadJourney()
        actions.loadFunnelQuery()
    }),
])
