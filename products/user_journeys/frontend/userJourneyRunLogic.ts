import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import type { ComparisonMode } from 'lib/components/VisualImageDiffViewer'
import { projectLogic } from 'scenes/projectLogic'
import { urls } from 'scenes/urls'

import type { Breadcrumb } from '~/types'

import { userJourneysRetrieve, userJourneysRunsRetrieve } from './generated/api'
import type { JourneyApi, JourneyRunDetailApi } from './generated/api.schemas'
import { RUN_POLL_INTERVAL_MS, defaultOpenStepIndexes, focusStepIndex, isRunActive, runSummary } from './journeyRuns'
import { JourneyLoadError, journeysBreadcrumb, toJourneyLoadError } from './journeySteps'
import { captureJourneyRunComparisonModeChanged, captureJourneyRunViewed } from './userJourneyEvents'

export type ScreenshotUrlsState = 'fresh' | 'refetching' | 'refetched' | 'unavailable'

/** Named after the route params, because the scene component renders with those. */
export interface UserJourneyRunLogicProps {
    /** The journey's ID. */
    id: string
    runId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userJourneyRunLogicValues {
    currentProjectId: number | null // projectLogic
    breadcrumbs: Breadcrumb[]
    comparisonMode: ComparisonMode
    focusedStepIndex: number | null
    journey: JourneyApi | null
    journeyLoading: boolean
    openStepIndexes: Set<number>
    run: JourneyRunDetailApi | null
    runLoadError: JourneyLoadError | null
    runLoading: boolean
    screenshotUrls: ScreenshotUrlsState
    stepOpenOverrides: Record<number, boolean>
    summary: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userJourneyRunLogicActions {
    loadJourney: () => any
    loadJourneyFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadJourneySuccess: (
        journey: JourneyApi,
        payload?: any
    ) => {
        journey: JourneyApi
        payload?: any
    }
    loadRun: () => any
    loadRunFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRunSuccess: (
        run: JourneyRunDetailApi,
        payload?: any
    ) => {
        run: JourneyRunDetailApi
        payload?: any
    }
    screenshotFailedToLoad: () => {
        value: true
    }
    setComparisonMode: (mode: ComparisonMode) => {
        mode: ComparisonMode
    }
    setStepOpen: (
        index: number,
        open: boolean
    ) => {
        index: number
        open: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userJourneyRunLogicMeta {
    key: any
}

export type userJourneyRunLogicType = MakeLogicType<
    userJourneyRunLogicValues,
    userJourneyRunLogicActions,
    UserJourneyRunLogicProps,
    userJourneyRunLogicMeta
>

export const userJourneyRunLogic = kea<userJourneyRunLogicType>([
    props({} as UserJourneyRunLogicProps),
    key((props) => `${props.id}/${props.runId}`),
    path((key) => ['products', 'user_journeys', 'frontend', 'userJourneyRunLogic', key]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        setStepOpen: (index: number, open: boolean) => ({ index, open }),
        setComparisonMode: (mode: ComparisonMode) => ({ mode }),
        screenshotFailedToLoad: true,
    }),
    loaders(({ props, values }) => ({
        run: [
            null as JourneyRunDetailApi | null,
            {
                loadRun: async () => userJourneysRunsRetrieve(String(values.currentProjectId), props.id, props.runId),
            },
        ],
        journey: [
            null as JourneyApi | null,
            {
                loadJourney: async () => {
                    try {
                        return await userJourneysRetrieve(String(values.currentProjectId), props.id)
                    } catch {
                        // Only the title and breadcrumb read the journey, so they fall back to generic names.
                        return null
                    }
                },
            },
        ],
    })),
    reducers({
        runLoadError: [
            null as JourneyLoadError | null,
            {
                loadRunSuccess: () => null,
                loadRunFailure: (_, { errorObject }) => toJourneyLoadError(errorObject),
            },
        ],
        stepOpenOverrides: [
            {} as Record<number, boolean>,
            {
                setStepOpen: (state, { index, open }) => ({ ...state, [index]: open }),
            },
        ],
        comparisonMode: [
            'sideBySide' as ComparisonMode,
            {
                setComparisonMode: (_, { mode }) => mode,
            },
        ],
        // Screenshot URLs expire after an hour, so the first broken image refetches the run for fresh URLs.
        // Images that break while that refetch is in flight still hold the old URLs, so they don't count.
        screenshotUrls: [
            'fresh' as ScreenshotUrlsState,
            {
                screenshotFailedToLoad: (state) =>
                    state === 'fresh' ? 'refetching' : state === 'refetched' ? 'unavailable' : state,
                loadRunSuccess: (state) => (state === 'refetching' ? 'refetched' : state),
                loadRunFailure: (state) => (state === 'refetching' ? 'unavailable' : state),
            },
        ],
    }),
    selectors({
        focusedStepIndex: [
            (s) => [s.run],
            (run: JourneyRunDetailApi | null): number | null => (run ? focusStepIndex(run.steps) : null),
        ],
        openStepIndexes: [
            (s) => [s.run, s.stepOpenOverrides],
            (run: JourneyRunDetailApi | null, overrides: Record<number, boolean>): Set<number> => {
                const defaults = defaultOpenStepIndexes(run?.steps ?? [])
                return new Set(
                    (run?.steps ?? [])
                        .filter((step) => overrides[step.index] ?? defaults.has(step.index))
                        .map((step) => step.index)
                )
            },
        ],
        summary: [(s) => [s.run], (run: JourneyRunDetailApi | null): string | null => (run ? runSummary(run) : null)],
        breadcrumbs: [
            (s) => [s.journey, (_, p) => p.id, (_, p) => p.runId],
            (journey: JourneyApi | null, journeyId: string, runId: string): Breadcrumb[] => [
                journeysBreadcrumb(),
                {
                    key: ['UserJourney', journeyId],
                    name: journey?.name ?? 'Journey',
                    path: urls.userJourney(journeyId),
                    iconType: 'insight/paths',
                },
                { key: ['UserJourneyRun', runId], name: 'Run', iconType: 'insight/paths' },
            ],
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const schedulePoll = (): void => {
            cache.disposables.add(() => {
                const timer = window.setTimeout(() => actions.loadRun(), RUN_POLL_INTERVAL_MS)
                return () => window.clearTimeout(timer)
            }, 'runPoll')
        }
        return {
            loadRunSuccess: ({ run }) => {
                if (isRunActive(run.status)) {
                    schedulePoll()
                    return
                }
                cache.disposables.dispose('runPoll')
                if (!cache.viewCaptured) {
                    cache.viewCaptured = true
                    captureJourneyRunViewed(run)
                }
            },
            loadRunFailure: () => {
                if (values.run && isRunActive(values.run.status)) {
                    schedulePoll()
                }
            },
            screenshotFailedToLoad: () => {
                if (values.screenshotUrls === 'refetching' && !values.runLoading) {
                    actions.loadRun()
                }
            },
            setComparisonMode: ({ mode }) => {
                captureJourneyRunComparisonModeChanged(mode)
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadRun()
        actions.loadJourney()
    }),
])
