export type userJourneyFormLogicType = MakeLogicType<
    userJourneyFormLogicValues,
    userJourneyFormLogicActions,
    UserJourneyFormLogicProps,
    userJourneyFormLogicMeta
>

export const userJourneyFormLogic = kea<userJourneyFormLogicType>([
    props({} as UserJourneyFormLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'user_journeys', 'frontend', 'userJourneyFormLogic', key]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        setName: (name: string) => ({ name }),
        setDescription: (description: string) => ({ description }),
        setConversionWindow: (minutes: number | undefined) => ({ minutes }),
        addStep: (type: JourneyStepType) => ({ type }),
        removeStep: (stepKey: string) => ({ stepKey }),
        moveStep: (stepKey: string, direction: -1 | 1) => ({ stepKey, direction }),
        updateStep: (stepKey: string, changes: JourneyStepChanges) => ({ stepKey, changes }),
        applyPrefill: (prefill: JourneyPrefill) => ({ prefill }),
        submit: true,
        saveJourney: true,
        saveJourneySuccess: (journey: JourneyApi) => ({ journey }),
        saveJourneyFailure: (errors: JourneyFormErrors) => ({ errors }),
    }),
    loaders(({ props, values }) => ({
        journey: [
            null as JourneyApi | null,
            {
                loadJourney: async () => userJourneysRetrieve(String(values.currentProjectId), props.id),
            },
        ],
    })),
    reducers({
        draft: [
            emptyDraft() as JourneyDraft,
            {
                setName: (state, { name }) => ({ ...state, name }),
                setDescription: (state, { description }) => ({ ...state, description }),
                setConversionWindow: (state, { minutes }) => ({ ...state, conversion_window_minutes: minutes }),
                addStep: (state, { type }) => ({ ...state, steps: [...state.steps, emptyStep(type)] }),
                removeStep: (state, { stepKey }) => ({
                    ...state,
                    steps: state.steps.filter((step) => step.key !== stepKey),
                }),
                moveStep: (state, { stepKey, direction }) => ({
                    ...state,
                    steps: moveStep(state.steps, stepKey, direction),
                }),
                updateStep: (state, { stepKey, changes }) => ({
                    ...state,
                    steps: state.steps.map((step) => (step.key === stepKey ? { ...step, ...changes } : step)),
                }),
                applyPrefill: (_, { prefill }) => prefill.draft,
                loadJourneySuccess: (state, { journey }) => (journey ? journeyToDraft(journey) : state),
            },
        ],
        submitAttempted: [
            false,
            {
                submit: () => true,
                applyPrefill: () => false,
                loadJourneySuccess: () => false,
            },
        ],
        serverErrors: [
            {} as JourneyFormErrors,
            {
                saveJourneyFailure: (_, { errors }) => errors,
                // The server reports errors by step position, so any edit can make them point at the wrong field.
                setName: () => ({}),
                setDescription: () => ({}),
                setConversionWindow: () => ({}),
                addStep: () => ({}),
                removeStep: () => ({}),
                moveStep: () => ({}),
                updateStep: () => ({}),
                saveJourney: () => ({}),
            },
        ],
        saving: [
            false,
            {
                saveJourney: () => true,
                saveJourneySuccess: () => false,
                saveJourneyFailure: () => false,
            },
        ],
        prefillStepsSkipped: [
            false,
            {
                applyPrefill: (_, { prefill }) => prefill.stepsSkipped,
            },
        ],
        journeyLoadError: [
            null as JourneyLoadError | null,
            {
                loadJourney: () => null,
                loadJourneyFailure: (_, { errorObject }) => toJourneyLoadError(errorObject),
            },
        ],
    }),
    selectors({
        isNew: [(_, p) => [p.id], (id: string): boolean => id === 'new'],
        validationErrors: [(s) => [s.draft], (draft: JourneyDraft): JourneyFormErrors => validateDraft(draft)],
        errors: [
            (s) => [s.validationErrors, s.serverErrors, s.submitAttempted],
            (
                validationErrors: JourneyFormErrors,
                serverErrors: JourneyFormErrors,
                submitAttempted: boolean
            ): JourneyFormErrors => (submitAttempted ? { ...validationErrors, ...serverErrors } : serverErrors),
        ],
        breadcrumbs: [
            (s) => [s.isNew, s.journey, (_, p) => p.id],
            (isNew: boolean, journey: JourneyApi | null, id: string): Breadcrumb[] => [
                journeysBreadcrumb(),
                ...(isNew
                    ? [{ key: 'UserJourneyNew', name: 'New journey', iconType: 'insight/paths' as const }]
                    : [
                          {
                              key: ['UserJourney', id] as [string, string],
                              name: journey?.name ?? 'Journey',
                              path: urls.userJourney(id),
                              iconType: 'insight/paths' as const,
                          },
                          {
                              key: ['UserJourneyEdit', id] as [string, string],
                              name: 'Edit',
                              iconType: 'insight/paths' as const,
                          },
                      ]),
            ],
        ],
    }),
    listeners(({ actions, values, props }) => ({
        submit: () => {
            const invalidFields = Object.keys(values.validationErrors)
            if (invalidFields.length > 0) {
                captureJourneySaveFailed(values.isNew ? 'create' : 'edit', 'invalid', invalidFields[0])
                return
            }
            actions.saveJourney()
        },
        saveJourney: async () => {
            const projectId = String(values.currentProjectId)
            const payload = draftToPayload(values.draft)
            try {
                const journey = values.isNew
                    ? await userJourneysCreate(projectId, payload)
                    : await userJourneysPartialUpdate(projectId, props.id, {
                          name: payload.name,
                          description: payload.description,
                          conversion_window_minutes: payload.conversion_window_minutes,
                          steps: payload.steps,
                      })
                actions.saveJourneySuccess(journey)
            } catch (error) {
                const fieldKey = error instanceof ApiError ? serverErrorKey(error.attr) : null
                captureJourneySaveFailed(values.isNew ? 'create' : 'edit', 'server', fieldKey)
                if (fieldKey && error instanceof ApiError) {
                    actions.saveJourneyFailure({ [fieldKey]: error.detail ?? 'Check this field.' })
                } else {
                    actions.saveJourneyFailure({})
                    lemonToast.error(
                        error instanceof ApiError && error.detail
                            ? error.detail
                            : "Couldn't save the journey. Try again, and if it keeps happening contact support."
                    )
                }
            }
        },
        saveJourneySuccess: ({ journey }) => {
            captureJourneySaved(values.isNew ? 'create' : 'edit', values.draft)
            lemonToast.success(values.isNew ? 'Journey created' : 'Journey saved')
            userJourneysLogic.findMounted()?.actions.loadJourneys()
            router.actions.push(urls.userJourney(journey.id))
        },
        loadJourneySuccess: ({ journey }) => {
            if (journey) {
                captureJourneyFormOpened('edit', false, journey.source)
            }
        },
    })),
    urlToAction(({ actions, values }) => ({
        '/user-journeys/new': (_, searchParams, __, { method, initial }) => {
            // Back and forward navigation keeps the half-filled form instead of resetting it from the link.
            if (!values.isNew || (method === 'POP' && !initial)) {
                return
            }
            const prefill = parseJourneyPrefill(searchParams)
            if (prefill) {
                actions.applyPrefill(prefill)
            }
            captureJourneyFormOpened('create', prefill !== null, prefill?.draft.source ?? 'manual')
        },
    })),
    afterMount(({ actions, values }) => {
        if (!values.isNew) {
            actions.loadJourney()
        }
    }),
])
