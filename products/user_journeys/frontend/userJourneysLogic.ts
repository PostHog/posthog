import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { projectLogic } from 'scenes/projectLogic'

import { userJourneysDestroy, userJourneysList } from './generated/api'
import type { JourneyApi } from './generated/api.schemas'
import { captureJourneyDeleted } from './userJourneyEvents'

// Journeys are hand-made, so one page at the API's maximum holds every journey a project has in practice.
const JOURNEYS_PAGE_SIZE = 1000

function withoutKey(state: Record<string, boolean>, id: string): Record<string, boolean> {
    const { [id]: _, ...rest } = state
    return rest
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userJourneysLogicValues {
    currentProjectId: number | null // projectLogic
    deletingJourneyIds: Record<string, boolean>
    journeys: JourneyApi[] | null
    journeysLoadFailed: boolean
    journeysLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userJourneysLogicActions {
    deleteJourney: (journey: JourneyApi) => {
        journey: JourneyApi
    }
    deleteJourneyFailed: (id: string) => {
        id: string
    }
    loadJourneys: () => any
    loadJourneysFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadJourneysSuccess: (
        journeys: JourneyApi[],
        payload?: any
    ) => {
        journeys: JourneyApi[]
        payload?: any
    }
    removeDeletedJourney: (id: string) => {
        id: string
    }
}

export type userJourneysLogicType = MakeLogicType<userJourneysLogicValues, userJourneysLogicActions>

export const userJourneysLogic = kea<userJourneysLogicType>([
    path(['products', 'user_journeys', 'frontend', 'userJourneysLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        deleteJourney: (journey: JourneyApi) => ({ journey }),
        removeDeletedJourney: (id: string) => ({ id }),
        deleteJourneyFailed: (id: string) => ({ id }),
    }),
    loaders(({ values }) => ({
        // null until the first load answers, so the list can tell "not loaded yet" apart from "no journeys"
        journeys: [
            null as JourneyApi[] | null,
            {
                loadJourneys: async () => {
                    const response = await userJourneysList(String(values.currentProjectId), {
                        limit: JOURNEYS_PAGE_SIZE,
                    })
                    return response.results
                },
            },
        ],
    })),
    reducers({
        journeysLoadFailed: [
            false,
            {
                loadJourneys: () => false,
                loadJourneysSuccess: () => false,
                loadJourneysFailure: () => true,
            },
        ],
        deletingJourneyIds: [
            {} as Record<string, boolean>,
            {
                deleteJourney: (state, { journey }) => ({ ...state, [journey.id]: true }),
                removeDeletedJourney: (state, { id }) => withoutKey(state, id),
                deleteJourneyFailed: (state, { id }) => withoutKey(state, id),
            },
        ],
        journeys: {
            removeDeletedJourney: (state, { id }) => state?.filter((journey) => journey.id !== id) ?? null,
        },
    }),
    listeners(({ actions, values }) => ({
        deleteJourney: async ({ journey }) => {
            try {
                await userJourneysDestroy(String(values.currentProjectId), journey.id)
                actions.removeDeletedJourney(journey.id)
                captureJourneyDeleted('list')
                lemonToast.success('Journey deleted')
            } catch {
                actions.deleteJourneyFailed(journey.id)
                lemonToast.error("Couldn't delete the journey. Try again.")
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadJourneys()
    }),
])
