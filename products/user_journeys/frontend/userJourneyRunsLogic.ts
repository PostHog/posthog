export type userJourneyRunsLogicType = MakeLogicType<
    userJourneyRunsLogicValues,
    userJourneyRunsLogicActions,
    UserJourneyRunsLogicProps,
    userJourneyRunsLogicMeta
>

export const userJourneyRunsLogic = kea<userJourneyRunsLogicType>([
    props({} as UserJourneyRunsLogicProps),
    key((props) => props.journeyId),
    path((key) => ['products', 'user_journeys', 'frontend', 'userJourneyRunsLogic', key]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        setPage: (page: number) => ({ page }),
        setRunFormOpen: (open: boolean) => ({ open }),
        setBaseUrl: (baseUrl: string) => ({ baseUrl }),
        startRun: true,
        startRunSuccess: (run: JourneyRunApi) => ({ run }),
        startRunFailure: (error: string | null, conflict: boolean) => ({ error, conflict }),
    }),
    loaders(({ props, values }) => ({
        // null until the first page answers, so the table can tell "not loaded yet" apart from "never run"
        runs: [
            null as JourneyRunsPage | null,
            {
                loadRuns: async (_, breakpoint) => {
                    const page = values.page
                    const response = await userJourneysRunsList(String(values.currentProjectId), props.journeyId, {
                        limit: RUNS_PAGE_SIZE,
                        offset: page * RUNS_PAGE_SIZE,
                    })
                    breakpoint()
                    return { page, count: response.count, results: response.results }
                },
            },
        ],
    })),
    reducers({
        page: [
            0,
            {
                setPage: (_, { page }) => page,
                startRunSuccess: () => 0,
            },
        ],
        runsLoadFailed: [
            false,
            {
                loadRunsSuccess: () => false,
                loadRunsFailure: () => true,
            },
        ],
        runFormOpen: [
            false,
            {
                setRunFormOpen: (_, { open }) => open,
                startRunSuccess: () => false,
            },
        ],
        baseUrl: [
            '',
            {
                setBaseUrl: (_, { baseUrl }) => baseUrl,
            },
        ],
        startingRun: [
            false,
            {
                startRun: () => true,
                startRunSuccess: () => false,
                startRunFailure: () => false,
            },
        ],
        startRunError: [
            null as string | null,
            {
                startRun: () => null,
                setBaseUrl: () => null,
                setRunFormOpen: () => null,
                startRunFailure: (_, { error }) => error,
            },
        ],
        runConflict: [
            false,
            {
                startRun: () => false,
                startRunSuccess: () => false,
                startRunFailure: (_, { conflict }) => conflict,
            },
        ],
    }),
    selectors({
        activeRun: [
            (s) => [s.runs],
            (runs: JourneyRunsPage | null): JourneyRunApi | null =>
                runs?.results.find((run) => isRunActive(run.status)) ?? null,
        ],
        baseUrlError: [
            (s) => [s.baseUrl],
            (baseUrl: string): string | null => (baseUrl.trim() ? runUrlError(baseUrl.trim()) : null),
        ],
        // Polls reload the page in place, so only a first load or a page change shows the table as loading.
        showRunsLoading: [
            (s) => [s.runsLoading, s.runs, s.page],
            (runsLoading: boolean, runs: JourneyRunsPage | null, page: number): boolean =>
                runsLoading && (runs === null || runs.page !== page),
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        // One timeout at a time, re-armed after each answer, so a slow response never stacks requests.
        const schedulePoll = (): void => {
            cache.disposables.add(() => {
                const timer = window.setTimeout(() => actions.loadRuns(), RUN_POLL_INTERVAL_MS)
                return () => window.clearTimeout(timer)
            }, 'runsPoll')
        }
        return {
            setPage: () => {
                actions.loadRuns()
            },
            loadRunsSuccess: ({ runs }) => {
                if (runs.results.some((run) => isRunActive(run.status))) {
                    schedulePoll()
                } else {
                    cache.disposables.dispose('runsPoll')
                }
            },
            loadRunsFailure: () => {
                // A failed poll keeps the last answer on screen and tries again, so a blip doesn't freeze a live run.
                if (values.activeRun) {
                    schedulePoll()
                }
            },
            startRun: async () => {
                const baseUrl = values.baseUrl.trim()
                if (values.baseUrlError) {
                    // The field already shows this error, so the failure carries no second copy of it.
                    actions.startRunFailure(null, false)
                    return
                }
                try {
                    const run = await userJourneysRunsCreate(String(values.currentProjectId), props.journeyId, {
                        base_url: baseUrl || null,
                    })
                    actions.startRunSuccess(run)
                    captureJourneyRunStarted(baseUrl !== '')
                } catch (error) {
                    const status = error instanceof ApiError ? error.status : undefined
                    if (status === 409) {
                        captureJourneyRunStartFailed('in_progress')
                        actions.startRunFailure(null, true)
                        actions.setRunFormOpen(false)
                        actions.loadRuns()
                    } else if (status === 400 && error instanceof ApiError) {
                        captureJourneyRunStartFailed('invalid')
                        actions.startRunFailure(
                            error.detail ?? "The run couldn't start. Check the URL and try again.",
                            false
                        )
                    } else {
                        captureJourneyRunStartFailed('server')
                        actions.startRunFailure(null, false)
                        lemonToast.error(
                            "Couldn't start the run. Try again, and if it keeps happening contact support."
                        )
                    }
                }
            },
            startRunSuccess: () => {
                lemonToast.success('Run started. Results appear here in a minute or less.')
                actions.loadRuns()
                userJourneysLogic.findMounted()?.actions.loadJourneys()
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadRuns()
    }),
])
