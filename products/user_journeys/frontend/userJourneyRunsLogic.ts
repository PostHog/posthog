import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiError } from 'lib/api-error'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { projectLogic } from 'scenes/projectLogic'

import { userJourneysRunsCreate, userJourneysRunsList } from './generated/api'
import type { JourneyRunApi } from './generated/api.schemas'
import { RUN_POLL_INTERVAL_MS, RUNS_PAGE_SIZE, isRunActive, runUrlError } from './journeyRuns'
import { captureJourneyRunStartFailed, captureJourneyRunStarted } from './userJourneyEvents'
import { userJourneysLogic } from './userJourneysLogic'

export interface UserJourneyRunsLogicProps {
    journeyId: string
}

export interface JourneyRunsPage {
    /** The page these runs are, from 0. */
    page: number
    count: number
    results: JourneyRunApi[]
}

