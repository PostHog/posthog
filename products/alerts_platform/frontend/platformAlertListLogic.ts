import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
} from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'

import { platformAlertsDestroy, platformAlertsList, platformAlertsPartialUpdate } from './generated/api'
import { PatchedPlatformAlertConfigurationEditApi, PlatformAlertConfigurationApi } from './generated/api.schemas'

const ALERT_POLL_INTERVAL_MS = 30_000

export interface PlatformAlertListLogicProps {
    /** The product whose alerts the list shows, such as traces. Keys the logic. */
    sourceKind: PatchedPlatformAlertConfigurationEditApi['source_kind']
    /** Each product's event names are frozen, so the caller passes them in full. */
    analyticsEvents: {
        deleted?: string
        enabledToggled: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface platformAlertListLogicValues {
    currentTeamId: number | null // teamLogic
    alerts: PlatformAlertConfigurationApi[]
    alertsLoadFailed: boolean
    alertsLoaded: boolean
    alertsLoading: boolean
    createdByFilter: string | null
    togglingAlertIds: Set<string>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface platformAlertListLogicActions {
    deleteAlert: (alert: PlatformAlertConfigurationApi) => {
        alert: PlatformAlertConfigurationApi
    }
    loadAlerts: (_?: any) => any
    loadAlertsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAlertsSuccess: (
        alerts: PlatformAlertConfigurationApi[],
        payload?: any
    ) => {
        alerts: PlatformAlertConfigurationApi[]
        payload?: any
    }
    setCreatedByFilter: (createdByFilter: string | null) => {
        createdByFilter: string | null
    }
    setTogglingAlertId: (
        id: string,
        toggling: boolean
    ) => {
        id: string
        toggling: boolean
    }
    toggleAlertEnabled: (alert: PlatformAlertConfigurationApi) => {
        alert: PlatformAlertConfigurationApi
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface platformAlertListLogicMeta {
    key: 'insight' | 'logs' | 'metrics' | 'traces' | 'warehouse_destination' | 'warehouse_source'
}

export type platformAlertListLogicType = MakeLogicType<
    platformAlertListLogicValues,
    platformAlertListLogicActions,
    PlatformAlertListLogicProps,
    platformAlertListLogicMeta
>

export const platformAlertListLogic: LogicWrapper<platformAlertListLogicType> = kea<platformAlertListLogicType>([
    props({} as PlatformAlertListLogicProps),
    key(({ sourceKind }) => sourceKind),
    path((key) => ['products', 'alerts_platform', 'frontend', 'platformAlertListLogic', key]),

    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    actions({
        deleteAlert: (alert: PlatformAlertConfigurationApi) => ({ alert }),
        toggleAlertEnabled: (alert: PlatformAlertConfigurationApi) => ({ alert }),
        setTogglingAlertId: (id: string, toggling: boolean) => ({ id, toggling }),
        setCreatedByFilter: (createdByFilter: string | null) => ({ createdByFilter }),
    }),

    loaders(({ props, values }) => ({
        alerts: [
            [] as PlatformAlertConfigurationApi[],
            {
                loadAlerts: async (_ = null, breakpoint) => {
                    // The platform caps alerts per team and product well under one page, so one request holds them all.
                    const response = await platformAlertsList(String(values.currentTeamId), {
                        source_kind: props.sourceKind,
                        limit: 100,
                        ...(values.createdByFilter ? { created_by: values.createdByFilter } : {}),
                    })
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),

    reducers({
        // An empty list only means the team has no alerts once a load has succeeded.
        alertsLoaded: [false, { loadAlertsSuccess: () => true }],
        // A poll that fails after a good load keeps the rows on screen rather than replacing them with an error.
        alertsLoadFailed: [false, { loadAlertsSuccess: () => false, loadAlertsFailure: () => true }],
        createdByFilter: [null as string | null, { setCreatedByFilter: (_, { createdByFilter }) => createdByFilter }],
        togglingAlertIds: [
            new Set<string>(),
            {
                setTogglingAlertId: (state, { id, toggling }) =>
                    toggling ? new Set([...state, id]) : new Set([...state].filter((x) => x !== id)),
            },
        ],
    }),

    listeners(({ actions, values, props }) => ({
        setCreatedByFilter: () => actions.loadAlerts(),
        deleteAlert: async ({ alert }) => {
            try {
                await platformAlertsDestroy(String(values.currentTeamId), alert.id)
                if (props.analyticsEvents.deleted) {
                    posthog.capture(props.analyticsEvents.deleted)
                }
                lemonToast.success('Alert deleted')
                actions.loadAlerts()
            } catch {
                lemonToast.error('Could not delete the alert. Try again.')
            }
        },
        toggleAlertEnabled: async ({ alert }) => {
            const enabled = !alert.enabled
            actions.setTogglingAlertId(alert.id, true)
            try {
                await platformAlertsPartialUpdate(String(values.currentTeamId), alert.id, {
                    source_kind: props.sourceKind,
                    enabled,
                })
                posthog.capture(props.analyticsEvents.enabledToggled, { enabled })
                actions.loadAlerts()
            } catch {
                lemonToast.error('Could not update the alert. Try again.')
            } finally {
                actions.setTogglingAlertId(alert.id, false)
            }
        },
    })),

    afterMount(({ actions, cache }) => {
        actions.loadAlerts()
        cache.disposables.add(() => {
            const intervalId = window.setInterval(() => actions.loadAlerts(), ALERT_POLL_INTERVAL_MS)
            return () => clearInterval(intervalId)
        }, 'pollAlerts')
    }),
])
