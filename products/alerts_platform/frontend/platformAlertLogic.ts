export const platformAlertLogic: LogicWrapper<platformAlertLogicType> = kea<platformAlertLogicType>([
    props({} as PlatformAlertLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'alerts_platform', 'frontend', 'platformAlertLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [teamLogic, ['loadCurrentTeamSuccess']],
    })),
    actions({
        snoozeGroupFor: (groupingKey: string, duration: GroupSnoozeDuration) => ({ groupingKey, duration }),
        snoozeGroupUntil: (groupingKey: string, snoozeUntil: string) => ({ groupingKey, snoozeUntil }),
        unsnoozeGroup: (groupingKey: string) => ({ groupingKey }),
        setGroupSnooze: (
            groupingKey: string,
            snoozeUntil: string | null,
            duration: GroupSnoozeDuration | 'custom' | null
        ) => ({ groupingKey, snoozeUntil, duration }),
        setGroupSnoozeSuccess: (alert: PlatformAlertApi) => ({ alert }),
        setGroupSnoozeFailure: true,
        openCustomSnooze: (groupingKey: string) => ({ groupingKey }),
        closeCustomSnooze: true,
        openRuleMetadataModal: true,
        closeRuleMetadataModal: true,
    }),
    forms(({ actions, values, props }) => ({
        ruleMetadataForm: {
            defaults: EMPTY_RULE_METADATA_FORM,
            // An array field takes one message for the whole list, which kea-forms renders but does not type.
            errors: ({ labels, annotations }: RuleMetadataForm) =>
                ({
                    labels: ruleMetadataEntriesError(labels),
                    annotations: ruleMetadataEntriesError(annotations),
                }) as DeepPartialMap<RuleMetadataForm, ValidationErrorType>,
            submit: async ({ labels, annotations }: RuleMetadataForm) => {
                try {
                    const updated = await platformAlertsPartialUpdate(String(values.currentTeamId), props.id, {
                        source_kind: values.configuration!.source_kind,
                        labels: ruleMetadataRecord(labels),
                        annotations: ruleMetadataRecord(annotations),
                    })
                    actions.loadConfigurationSuccess(updated)
                } catch (error) {
                    actions.setRuleMetadataFormManualErrors(fieldError(error, RULE_METADATA_FIELD_BY_ATTR))
                    throw error
                }
            },
        },
    })),
    loaders(({ values, props }) => ({
        configuration: [
            null as PlatformAlertConfigurationApi | null,
            {
                loadConfiguration: async () => {
                    if (!values.currentTeamId) {
                        return values.configuration
                    }
                    return await platformAlertsRetrieve(String(values.currentTeamId), props.id)
                },
            },
        ],
    })),
    reducers({
        configuration: {
            setGroupSnoozeSuccess: (configuration, { alert }) =>
                configuration && {
                    ...configuration,
                    alerts: configuration.alerts.map((existing) => (existing.id === alert.id ? alert : existing)),
                },
        },
        configurationError: [
            false,
            {
                loadConfiguration: () => false,
                loadConfigurationFailure: () => true,
            },
        ],
        snoozingGroupKey: [
            null as string | null,
            {
                setGroupSnooze: (_, { groupingKey }) => groupingKey,
                setGroupSnoozeSuccess: () => null,
                setGroupSnoozeFailure: () => null,
            },
        ],
        ruleMetadataModalOpen: [
            false,
            {
                openRuleMetadataModal: () => true,
                closeRuleMetadataModal: () => false,
                submitRuleMetadataFormSuccess: () => false,
            },
        ],
        customSnoozeGroupKey: [
            null as string | null,
            {
                openCustomSnooze: (_, { groupingKey }) => groupingKey,
                closeCustomSnooze: () => null,
                setGroupSnoozeSuccess: () => null,
            },
        ],
    }),
    selectors({
        breadcrumbs: [
            (s) => [s.configuration, (_, props) => props.id],
            (configuration: PlatformAlertConfigurationApi | null, id: string): Breadcrumb[] => [
                PLATFORM_ALERTS_BREADCRUMB,
                {
                    key: [Scene.PlatformAlert, id],
                    name: configuration?.name ?? 'Alert',
                },
            ],
        ],
        // The API reports each group's snooze as the later of its own and the whole alert's, so a
        // group under an alert-wide snooze has no snooze of its own that this page could clear.
        alertSnoozeUntil: [
            (s) => [s.configuration],
            (configuration: PlatformAlertConfigurationApi | null): string | null =>
                configuration?.snooze_until && dayjs(configuration.snooze_until).isAfter(dayjs())
                    ? configuration.snooze_until
                    : null,
        ],
        // The API refuses a group snooze on a source-owned alert (409) and on an ungrouped one (400).
        canSnoozeGroups: [
            (s) => [s.configuration],
            (configuration: PlatformAlertConfigurationApi | null): boolean =>
                configuration?.owner === PlatformAlertOwnerEnumApi.Platform &&
                configuration.grouping.mode === GroupingModeEnumApi.ByResultLabels,
        ],
        // The API refuses an edit to a source-owned alert (409). Its source product edits it.
        canEditRuleMetadata: [
            (s) => [s.configuration],
            (configuration: PlatformAlertConfigurationApi | null): boolean =>
                configuration?.owner === PlatformAlertOwnerEnumApi.Platform,
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        loadCurrentTeamSuccess: () => {
            actions.loadConfiguration()
        },
        loadConfigurationSuccess: ({ configuration }) => {
            const snoozeUntil = configuration?.snooze_until
            if (!snoozeUntil || !dayjs(snoozeUntil).isAfter(dayjs())) {
                cache.disposables.dispose('alertSnoozeExpiry')
                return
            }
            // `alertSnoozeUntil` reads the clock only when the configuration changes, so reload at expiry.
            // A wait past the timer limit fires early, and the reload arms the next one.
            cache.disposables.add(() => {
                const delay = Math.min(Math.max(dayjs(snoozeUntil).diff(dayjs()), 0) + 1000, MAX_TIMER_DELAY_MS)
                const timer = setTimeout(() => actions.loadConfiguration(), delay)
                return () => clearTimeout(timer)
            }, 'alertSnoozeExpiry')
        },
        openRuleMetadataModal: () => {
            actions.resetRuleMetadataForm({
                labels: ruleMetadataEntries(values.configuration?.labels ?? {}),
                annotations: ruleMetadataEntries(values.configuration?.annotations ?? {}),
            })
            // pinned: analytics event names and properties. Renaming them breaks dashboards.
            posthog.capture('platform alert rule metadata edit opened', {
                configuration_id: props.id,
                source_kind: values.configuration?.source_kind,
            })
        },
        submitRuleMetadataFormFailure: ({ error }) => {
            if (!Object.keys(fieldError(error, RULE_METADATA_FIELD_BY_ATTR)).length) {
                lemonToast.error(`Couldn't save labels and annotations. ${errorMessage(error)}`)
            }
        },
        // A server error can name the other field, such as an annotation that references a removed
        // label, and kea-forms clears it only when that field changes.
        setRuleMetadataFormValue: () => {
            if (Object.keys(values.ruleMetadataFormManualErrors).length) {
                actions.setRuleMetadataFormManualErrors({})
            }
        },
        submitRuleMetadataFormSuccess: () => {
            // pinned: analytics event names and properties. Renaming them breaks dashboards.
            posthog.capture('platform alert rule metadata saved', {
                configuration_id: props.id,
                source_kind: values.configuration?.source_kind,
                label_count: Object.keys(values.configuration?.labels ?? {}).length,
                annotation_count: Object.keys(values.configuration?.annotations ?? {}).length,
            })
            lemonToast.success('Labels and annotations saved')
        },
        snoozeGroupFor: ({ groupingKey, duration }) => {
            const { hours } = GROUP_SNOOZE_DURATIONS.find((option) => option.duration === duration)!
            actions.setGroupSnooze(groupingKey, dayjs().add(hours, 'hour').toISOString(), duration)
        },
        snoozeGroupUntil: ({ groupingKey, snoozeUntil }) => {
            actions.setGroupSnooze(groupingKey, snoozeUntil, 'custom')
        },
        unsnoozeGroup: ({ groupingKey }) => {
            actions.setGroupSnooze(groupingKey, null, null)
        },
        setGroupSnooze: async ({ groupingKey, snoozeUntil, duration }) => {
            if (!values.currentTeamId) {
                actions.setGroupSnoozeFailure()
                return
            }
            try {
                const alert = await platformAlertsSnoozeGroupCreate(String(values.currentTeamId), props.id, {
                    grouping_key: groupingKey,
                    snooze_until: snoozeUntil,
                })
                actions.setGroupSnoozeSuccess(alert)
                // pinned: analytics event names and properties. Renaming them breaks dashboards.
                posthog.capture(snoozeUntil ? 'platform alert group snoozed' : 'platform alert group unsnoozed', {
                    configuration_id: props.id,
                    source_kind: values.configuration?.source_kind,
                    duration,
                })
                lemonToast.success(snoozeUntil ? 'Group snoozed' : 'Group unsnoozed')
            } catch (error: any) {
                actions.setGroupSnoozeFailure()
                lemonToast.error(
                    error?.detail ??
                        (snoozeUntil
                            ? "Couldn't snooze this group. Try again."
                            : "Couldn't unsnooze this group. Try again.")
                )
                // A quiet group is removed, so a 404 means the table is stale.
                if (error?.status === 404) {
                    actions.closeCustomSnooze()
                    actions.loadConfiguration()
                }
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadConfiguration()
    }),
])
