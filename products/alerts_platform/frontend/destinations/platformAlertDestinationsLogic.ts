function destinationsApi(props: PlatformAlertDestinationsLogicProps): AlertDestinationsApi {
    return props.api ?? PLATFORM_DESTINATIONS_API
}

export const platformAlertDestinationsLogic = kea<platformAlertDestinationsLogicType>([
    path((key) => ['products', 'alerts_platform', 'frontend', 'destinations', 'platformAlertDestinationsLogic', key]),
    props({} as PlatformAlertDestinationsLogicProps),
    key(({ alertId, sourceKind }) => `${sourceKind}-${alertId ?? 'new'}`),

    connect({
        values: [teamLogic, ['currentTeamId'], integrationsLogic, ['integrationsLoading', 'slackIntegrations']],
        actions: [integrationsLogic, ['loadIntegrations', 'loadIntegrationsFailure', 'loadIntegrationsSuccess']],
    }),

    actions({
        setSelectedType: (selectedType: PlatformAlertDestinationTypeEnumApi) => ({ selectedType }),
        setSlackChannelValue: (slackChannelValue: string | null) => ({ slackChannelValue }),
        setWebhookUrl: (webhookUrl: string) => ({ webhookUrl }),
        setPagerDutyRoutingKey: (pagerDutyRoutingKey: string) => ({ pagerDutyRoutingKey }),
        setPagerDutySeverity: (pagerDutySeverity: AlertPagerDutySeverity) => ({ pagerDutySeverity }),
        setPagerDutyRegion: (pagerDutyRegion: AlertPagerDutyRegion) => ({ pagerDutyRegion }),
        addSelectedDestination: true,
        addPendingDestination: (destination: PlatformAlertCreateDestinationApi) => ({ destination }),
        removePendingDestination: (index: number) => ({ index }),
        setPendingDestinations: (destinations: PlatformAlertCreateDestinationApi[]) => ({ destinations }),
        createPendingDestinations: (alertId: string) => ({ alertId }),
        deleteDestination: (destination: AlertDestinationEntry) => ({ destination }),
        setDeletingDestinationId: (id: string, deleting: boolean) => ({ id, deleting }),
        setSelectedSlackIntegrationId: (integrationId: number | null) => ({ integrationId }),
        setSavingDestinations: (saving: boolean) => ({ saving }),
        // After a destination was added or removed, for a page that shows more of the alert than its destinations.
        destinationsChanged: true,
    }),

    loaders(({ props, values }) => ({
        destinations: [
            [] as AlertDestinationEntry[],
            {
                loadDestinations: async () => {
                    if (!props.alertId) {
                        return []
                    }
                    return await destinationsApi(props).list(String(values.currentTeamId), props.alertId)
                },
            },
        ],
    })),

    reducers({
        selectedType: [
            PlatformAlertDestinationTypeEnumApi.Slack as PlatformAlertDestinationTypeEnumApi,
            { setSelectedType: (_, { selectedType }) => selectedType },
        ],
        slackChannelValue: [
            null as string | null,
            {
                setSlackChannelValue: (_, { slackChannelValue }) => slackChannelValue,
                // A channel belongs to one workspace.
                setSelectedSlackIntegrationId: () => null,
            },
        ],
        webhookUrl: ['', { setWebhookUrl: (_, { webhookUrl }) => webhookUrl }],
        pagerDutyRoutingKey: ['', { setPagerDutyRoutingKey: (_, { pagerDutyRoutingKey }) => pagerDutyRoutingKey }],
        pagerDutySeverity: [
            'critical' as AlertPagerDutySeverity,
            { setPagerDutySeverity: (_, { pagerDutySeverity }) => pagerDutySeverity },
        ],
        pagerDutyRegion: [
            'us' as AlertPagerDutyRegion,
            { setPagerDutyRegion: (_, { pagerDutyRegion }) => pagerDutyRegion },
        ],
        pendingDestinations: [
            [] as PlatformAlertCreateDestinationApi[],
            {
                addPendingDestination: (state, { destination }) => [...state, destination],
                removePendingDestination: (state, { index }) => state.filter((_, i) => i !== index),
                setPendingDestinations: (_, { destinations }) => destinations,
            },
        ],
        deletingDestinationIds: [
            new Set<string>(),
            {
                setDeletingDestinationId: (state, { id, deleting }) =>
                    deleting ? new Set([...state, id]) : new Set([...state].filter((x) => x !== id)),
            },
        ],
        selectedSlackIntegrationId: [
            null as number | null,
            { setSelectedSlackIntegrationId: (_, { integrationId }) => integrationId },
        ],
        savingDestinations: [false, { setSavingDestinations: (_, { saving }) => saving }],
        // The list stays empty on a failed load, so the editor needs this to tell it apart from no destinations.
        destinationsLoadFailed: [
            false,
            {
                loadDestinations: () => false,
                loadDestinationsSuccess: () => false,
                loadDestinationsFailure: () => true,
            },
        ],
        integrationsFailed: [
            false,
            {
                loadIntegrations: () => false,
                loadIntegrationsFailure: () => true,
                loadIntegrationsSuccess: () => false,
            },
        ],
    }),

    selectors({
        slackIntegration: [
            (s) => [s.slackIntegrations, s.selectedSlackIntegrationId],
            (
                slackIntegrations: IntegrationType[] | undefined,
                selectedSlackIntegrationId: number | null
            ): IntegrationType | undefined =>
                slackIntegrations?.find((integration) => integration.id === selectedSlackIntegrationId) ??
                slackIntegrations?.[0],
        ],
        urlInput: [
            (s) => [s.selectedType],
            (selectedType: PlatformAlertDestinationTypeEnumApi): AlertNotificationUrlInput | undefined =>
                urlInputFor(selectedType),
        ],
        addDisabledReason: [
            (s) => [
                s.destinations,
                s.pendingDestinations,
                s.savingDestinations,
                s.selectedType,
                s.slackIntegration,
                s.slackChannelValue,
                s.webhookUrl,
                s.pagerDutyRoutingKey,
            ],
            (
                destinations: AlertDestinationEntry[],
                pendingDestinations: PlatformAlertCreateDestinationApi[],
                savingDestinations: boolean,
                selectedType: PlatformAlertDestinationTypeEnumApi,
                slackIntegration: IntegrationType | undefined,
                slackChannelValue: string | null,
                webhookUrl: string,
                pagerDutyRoutingKey: string
            ): string | undefined => {
                if (savingDestinations) {
                    return 'Saving the last destination'
                }
                if (destinations.length + pendingDestinations.length >= MAX_DESTINATIONS_PER_ALERT) {
                    return `An alert can have at most ${MAX_DESTINATIONS_PER_ALERT} destinations`
                }
                if (selectedType === PlatformAlertDestinationTypeEnumApi.Pagerduty) {
                    return pagerDutyRoutingKeyError(pagerDutyRoutingKey)
                }
                if (selectedType === PlatformAlertDestinationTypeEnumApi.Slack) {
                    if (!slackIntegration) {
                        return 'Connect Slack first'
                    }
                    return slackChannelValue ? undefined : 'Select a Slack channel'
                }
                return destinationUrlError(selectedType, webhookUrl)
            },
        ],
    }),

    listeners(({ actions, values, props }) => ({
        addSelectedDestination: () => {
            if (values.addDisabledReason) {
                return
            }
            const type = values.selectedType
            if (type === PlatformAlertDestinationTypeEnumApi.Slack) {
                const [channelId, channelLabel] = (values.slackChannelValue ?? '').split('|')
                actions.addPendingDestination({
                    type,
                    slack_workspace_id: values.slackIntegration?.id,
                    slack_channel_id: channelId,
                    slack_channel_name: channelLabel?.replace('#', '') || channelId,
                })
                actions.setSlackChannelValue(null)
            } else if (type === PlatformAlertDestinationTypeEnumApi.Pagerduty) {
                const routingKey = values.pagerDutyRoutingKey.trim()
                if (!PAGERDUTY_ROUTING_KEY_PATTERN.test(routingKey)) {
                    return
                }
                actions.addPendingDestination({
                    type,
                    pagerduty_routing_key: routingKey,
                    pagerduty_severity: values.pagerDutySeverity,
                    pagerduty_region: values.pagerDutyRegion,
                })
                actions.setPagerDutyRoutingKey('')
            } else {
                actions.addPendingDestination({ type, webhook_url: values.webhookUrl.trim() })
                actions.setWebhookUrl('')
            }
        },
        // A saved alert takes each destination as soon as it is added, as the logs alert editor does.
        addPendingDestination: () => {
            if (props.alertId) {
                actions.createPendingDestinations(props.alertId)
            }
        },
        createPendingDestinations: async ({ alertId }) => {
            if (values.savingDestinations) {
                return
            }
            actions.setSavingDestinations(true)
            const projectId = String(values.currentTeamId)
            const batch = values.pendingDestinations
            const failed: PlatformAlertCreateDestinationApi[] = []
            for (const destination of batch) {
                // A destination removed while the batch was saving is not sent.
                if (!values.pendingDestinations.includes(destination)) {
                    continue
                }
                try {
                    await destinationsApi(props).create(projectId, alertId, destination)
                    posthog.capture('alert destination added', {
                        source_kind: props.sourceKind,
                        destination_type: destination.type,
                    })
                } catch {
                    failed.push(destination)
                }
            }
            const stillPending = values.pendingDestinations
            actions.setPendingDestinations([
                // A failed one stays to retry, unless it was removed while the batch saved.
                ...failed.filter((destination) => stillPending.includes(destination)),
                ...stillPending.filter((destination) => !batch.includes(destination)),
            ])
            actions.setSavingDestinations(false)
            if (failed.length > 0) {
                lemonToast.error('Could not add every notification destination. Check them and try again.')
            }
            if (props.alertId) {
                actions.loadDestinations()
            }
            if (failed.length < batch.length) {
                actions.destinationsChanged()
            }
        },
        deleteDestination: async ({ destination }) => {
            if (!props.alertId) {
                return
            }
            actions.setDeletingDestinationId(destination.id, true)
            try {
                await destinationsApi(props).remove(String(values.currentTeamId), props.alertId, destination)
                posthog.capture('alert destination removed', {
                    source_kind: props.sourceKind,
                    destination_type: destination.type,
                })
                actions.loadDestinations()
                actions.destinationsChanged()
            } catch {
                lemonToast.error('Could not remove the destination. Try again.')
            } finally {
                actions.setDeletingDestinationId(destination.id, false)
            }
        },
        loadIntegrationsSuccess: () => {
            if (!values.slackIntegration && values.selectedType === PlatformAlertDestinationTypeEnumApi.Slack) {
                actions.setSelectedType(PlatformAlertDestinationTypeEnumApi.Webhook)
            }
        },
    })),

    afterMount(({ actions, props }) => {
        if (props.alertId) {
            actions.loadDestinations()
        }
    }),
])
