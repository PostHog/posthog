function errorDetail(error: unknown): string | undefined {
    return (error as ApiError | undefined)?.detail ?? undefined
}

/** Adds each pending destination to a newly created alert. Returns how many could not be added. */
export async function createPendingDestinations(
    projectId: string,
    alertId: string,
    destinations: PlatformAlertCreateDestinationApi[]
): Promise<number> {
    const results = await Promise.allSettled(
        destinations.map((destination) => platformAlertsDestinationsCreate(projectId, alertId, destination))
    )
    return results.filter((result) => result.status === 'rejected').length
}

export const platformAlertDestinationsLogic = kea<platformAlertDestinationsLogicType>([
    path((key) => ['products', 'alerts_platform', 'frontend', 'destinations', 'platformAlertDestinationsLogic', key]),
    props({} as PlatformAlertDestinationsLogicProps),
    key(({ alertId, sourceKind }) => `${sourceKind}-${alertId ?? 'new'}`),

    connect(() => ({
        values: [teamLogic, ['currentTeamId'], integrationsLogic, ['slackIntegrations', 'integrationsLoading']],
    })),

    actions({
        addPendingDestination: (destination: PlatformAlertCreateDestinationApi) => ({ destination }),
        removePendingDestination: (index: number) => ({ index }),
        removeDestination: (id: string) => ({ id }),
        setRemovingDestinationId: (id: string, removing: boolean) => ({ id, removing }),
        startAddingDestination: true,
        cancelAddingDestination: true,
    }),

    loaders(({ props, values }) => ({
        destinations: [
            null as PlatformAlertDestinationApi[] | null,
            {
                loadDestinations: async () => {
                    if (!props.alertId) {
                        return []
                    }
                    return await platformAlertsDestinationsList(String(values.currentTeamId), props.alertId)
                },
            },
        ],
    })),

    reducers({
        pendingDestinations: [
            [] as PlatformAlertCreateDestinationApi[],
            {
                addPendingDestination: (state, { destination }) => [...state, destination],
                removePendingDestination: (state, { index }) => state.filter((_, i) => i !== index),
            },
        ],
        removingDestinationIds: [
            new Set<string>(),
            {
                setRemovingDestinationId: (state, { id, removing }) =>
                    removing ? new Set([...state, id]) : new Set([...state].filter((x) => x !== id)),
            },
        ],
        isAddingDestination: [
            false,
            {
                startAddingDestination: () => true,
                cancelAddingDestination: () => false,
                submitDestinationFormSuccess: () => false,
            },
        ],
    }),

    forms(({ props, values, actions }) => ({
        destinationForm: {
            defaults: EMPTY_DESTINATION_FORM,
            errors: validateDestinationForm,
            submit: async (form) => {
                const body = destinationBody(form, values.slackIntegration?.id)
                if (!props.alertId) {
                    actions.addPendingDestination(body)
                } else {
                    try {
                        await platformAlertsDestinationsCreate(String(values.currentTeamId), props.alertId, body)
                    } catch (error) {
                        const detail = errorDetail(error)
                        lemonToast.error(
                            detail ? `Could not add the destination: ${detail}` : 'Could not add the destination.'
                        )
                        throw error
                    }
                    actions.loadDestinations()
                }
                posthog.capture('alert destination added', {
                    source_kind: props.sourceKind,
                    type: body.type,
                    pending: !props.alertId,
                })
                actions.resetDestinationForm(EMPTY_DESTINATION_FORM)
                return form
            },
        },
    })),

    // After forms, because slackIntegration reads the destination form.
    selectors({
        slackIntegration: [
            (s) => [s.slackIntegrations, s.destinationForm],
            (
                slackIntegrations: IntegrationType[] | undefined,
                destinationForm: DestinationForm
            ): IntegrationType | undefined =>
                slackIntegrations?.find((integration) => integration.id === destinationForm.slackWorkspaceId) ??
                slackIntegrations?.[0],
        ],
    }),

    listeners(({ actions, values, props }) => ({
        startAddingDestination: () => {
            actions.resetDestinationForm(EMPTY_DESTINATION_FORM)
        },
        removeDestination: async ({ id }) => {
            if (!props.alertId) {
                return
            }
            actions.setRemovingDestinationId(id, true)
            try {
                await platformAlertsDestinationsDeleteCreate(String(values.currentTeamId), props.alertId, {
                    destination_ids: [id],
                })
                posthog.capture('alert destination removed', { source_kind: props.sourceKind })
                actions.loadDestinations()
            } catch (error) {
                const detail = errorDetail(error)
                lemonToast.error(
                    detail ? `Could not remove the destination: ${detail}` : 'Could not remove the destination.'
                )
            } finally {
                actions.setRemovingDestinationId(id, false)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadDestinations()
    }),
])
