export const platformAlertRoutingLogic = kea<platformAlertRoutingLogicType>([
    path(['products', 'alerts_platform', 'frontend', 'routing', 'platformAlertRoutingLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            integrationsLogic,
            ['slackIntegrations', 'integrationsLoading'],
            organizationLogic,
            ['isAdminOrOwner'],
        ],
        actions: [teamLogic, ['loadCurrentTeamSuccess']],
    })),
    actions({
        openReceiverModal: (receiver: AlertReceiverApi | null) => ({ receiver }),
        closeReceiverModal: true,
        openRouteModal: (route: AlertRouteApi | null) => ({ route }),
        closeRouteModal: true,
        setReceiverEnabled: (receiver: AlertReceiverApi, enabled: boolean) => ({ receiver, enabled }),
        setRouteEnabled: (route: AlertRouteApi, enabled: boolean) => ({ route, enabled }),
        deleteReceiver: (receiver: AlertReceiverApi) => ({ receiver }),
        deleteRoute: (route: AlertRouteApi) => ({ route }),
        toggleFinished: (id: string) => ({ id }),
    }),
    loaders(({ values }) => ({
        receivers: [
            null as AlertReceiverApi[] | null,
            {
                loadReceivers: async (_: void, breakpoint) => {
                    if (!values.currentTeamId) {
                        return values.receivers
                    }
                    const receivers = await platformAlertReceiversList(String(values.currentTeamId))
                    // Drops this response when a newer load started while it was in flight.
                    breakpoint()
                    return receivers
                },
            },
        ],
        routes: [
            null as AlertRouteApi[] | null,
            {
                loadRoutes: async (_: void, breakpoint) => {
                    if (!values.currentTeamId) {
                        return values.routes
                    }
                    const routes = await platformAlertRoutesList(String(values.currentTeamId))
                    breakpoint()
                    return routes
                },
            },
        ],
    })),
    reducers({
        receiversError: [false, { loadReceivers: () => false, loadReceiversFailure: () => true }],
        routesError: [false, { loadRoutes: () => false, loadRoutesFailure: () => true }],
        togglingIds: [
            [] as string[],
            {
                setReceiverEnabled: (ids, { receiver }) => [...ids, receiver.id],
                setRouteEnabled: (ids, { route }) => [...ids, route.id],
                toggleFinished: (ids, { id }) => ids.filter((togglingId) => togglingId !== id),
            },
        ],
        receiverModalOpen: [false, { openReceiverModal: () => true, closeReceiverModal: () => false }],
        editingReceiver: [
            null as AlertReceiverApi | null,
            { openReceiverModal: (_, { receiver }) => receiver, closeReceiverModal: () => null },
        ],
        routeModalOpen: [false, { openRouteModal: () => true, closeRouteModal: () => false }],
        editingRoute: [
            null as AlertRouteApi | null,
            { openRouteModal: (_, { route }) => route, closeRouteModal: () => null },
        ],
    }),
    forms(({ values, actions }) => ({
        receiverForm: {
            defaults: EMPTY_RECEIVER_FORM,
            errors: (form: ReceiverForm) => receiverFormErrors(form, values.editingReceiver),
            submit: async (form: ReceiverForm) => {
                const teamId = String(values.currentTeamId)
                const editing = values.editingReceiver
                const destination = receiverDestinationBody(form, values.slackIntegration?.id, editing)
                try {
                    if (editing) {
                        await platformAlertReceiversPartialUpdate(teamId, editing.id, {
                            name: form.name.trim(),
                            ...destination,
                        })
                    } else {
                        await platformAlertReceiversCreate(teamId, { name: form.name.trim(), ...destination! })
                    }
                } catch (error) {
                    const fieldErrors = fieldError(error, RECEIVER_FIELD_BY_ATTR)
                    if (Object.keys(fieldErrors).length) {
                        actions.setReceiverFormManualErrors(fieldErrors)
                    } else {
                        lemonToast.error(`Couldn't save the receiver. ${errorMessage(error)}`)
                    }
                    throw error
                }
            },
        },
        routeForm: {
            defaults: EMPTY_ROUTE_FORM,
            // An array field takes one message for the whole list, which kea-forms renders but does not type.
            errors: (form: RouteForm) => routeFormErrors(form) as DeepPartialMap<RouteForm, ValidationErrorType>,
            submit: async (form: RouteForm) => {
                const teamId = String(values.currentTeamId)
                const body = {
                    receiver_id: form.receiverId!,
                    matchers: trimmedMatchers(form.matchers),
                    event_kinds: form.eventKinds,
                }
                try {
                    if (values.editingRoute) {
                        await platformAlertRoutesPartialUpdate(teamId, values.editingRoute.id, body)
                    } else {
                        await platformAlertRoutesCreate(teamId, body)
                    }
                } catch (error) {
                    const fieldErrors = fieldError(error, ROUTE_FIELD_BY_ATTR)
                    if (Object.keys(fieldErrors).length) {
                        actions.setRouteFormManualErrors(fieldErrors)
                    } else {
                        lemonToast.error(`Couldn't save the route. ${errorMessage(error)}`)
                    }
                    throw error
                }
            },
        },
    })),
    // After forms, because slackIntegration reads the receiver form.
    selectors({
        // Mirrors the API, which lets only organization admins change routing.
        editDisabledReason: [
            (s) => [s.isAdminOrOwner],
            (isAdminOrOwner: boolean | null): string | null =>
                isAdminOrOwner ? null : 'Only organization admins can change alert routing',
        ],
        slackIntegration: [
            (s) => [s.slackIntegrations, s.receiverForm],
            (
                slackIntegrations: IntegrationType[] | undefined,
                receiverForm: ReceiverForm
            ): IntegrationType | undefined =>
                slackIntegrations?.find((integration) => integration.id === receiverForm.slackWorkspaceId) ??
                slackIntegrations?.[0],
        ],
        receiversById: [
            (s) => [s.receivers],
            (receivers: AlertReceiverApi[] | null): Record<string, AlertReceiverApi> =>
                Object.fromEntries((receivers ?? []).map((receiver) => [receiver.id, receiver])),
        ],
    }),
    listeners(({ actions, values }) => ({
        openReceiverModal: ({ receiver }) => {
            actions.resetReceiverForm(receiver ? receiverFormFor(receiver) : EMPTY_RECEIVER_FORM)
        },
        openRouteModal: ({ route }) => {
            actions.resetRouteForm(
                route ? routeFormFor(route) : { ...EMPTY_ROUTE_FORM, receiverId: values.receivers?.[0]?.id ?? null }
            )
        },
        submitReceiverFormSuccess: () => {
            lemonToast.success(values.editingReceiver ? 'Receiver saved' : 'Receiver added')
            actions.closeReceiverModal()
            actions.loadReceivers()
        },
        submitRouteFormSuccess: () => {
            lemonToast.success(values.editingRoute ? 'Route saved' : 'Route added')
            actions.closeRouteModal()
            actions.loadRoutes()
            // The receivers table counts each receiver's routes.
            actions.loadReceivers()
        },
        setReceiverEnabled: async ({ receiver, enabled }) => {
            try {
                await platformAlertReceiversPartialUpdate(String(values.currentTeamId), receiver.id, { enabled })
            } catch (error) {
                lemonToast.error(`Couldn't update the receiver. ${errorMessage(error)}`)
            }
            actions.toggleFinished(receiver.id)
            actions.loadReceivers()
        },
        setRouteEnabled: async ({ route, enabled }) => {
            try {
                await platformAlertRoutesPartialUpdate(String(values.currentTeamId), route.id, { enabled })
            } catch (error) {
                lemonToast.error(`Couldn't update the route. ${errorMessage(error)}`)
            }
            actions.toggleFinished(route.id)
            actions.loadRoutes()
        },
        loadCurrentTeamSuccess: () => {
            actions.loadReceivers()
            actions.loadRoutes()
        },
        deleteReceiver: ({ receiver }) => {
            const routeCount = receiver.route_count
            LemonDialog.open({
                title: `Delete receiver "${receiver.name}"?`,
                description:
                    routeCount > 0
                        ? `This also deletes the ${routeCount === 1 ? 'route' : `${routeCount} routes`} that send to it. Alerts stop sending to this destination through routing.`
                        : 'Alerts stop sending to this destination through routing.',
                primaryButton: {
                    children: 'Delete',
                    status: 'danger',
                    'data-attr': 'platform-alert-receiver-delete-confirm',
                    onClick: async () => {
                        try {
                            await platformAlertReceiversDestroy(String(values.currentTeamId), receiver.id)
                            lemonToast.success('Receiver deleted')
                        } catch (error) {
                            lemonToast.error(`Couldn't delete the receiver. ${errorMessage(error)}`)
                        }
                        actions.loadReceivers()
                        actions.loadRoutes()
                    },
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        deleteRoute: ({ route }) => {
            LemonDialog.open({
                title: 'Delete route?',
                description: 'Alerts that match it stop sending to its receiver.',
                primaryButton: {
                    children: 'Delete',
                    status: 'danger',
                    'data-attr': 'platform-alert-route-delete-confirm',
                    onClick: async () => {
                        try {
                            await platformAlertRoutesDestroy(String(values.currentTeamId), route.id)
                            lemonToast.success('Route deleted')
                        } catch (error) {
                            lemonToast.error(`Couldn't delete the route. ${errorMessage(error)}`)
                        }
                        actions.loadRoutes()
                        actions.loadReceivers()
                    },
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadReceivers()
        actions.loadRoutes()
    }),
])
