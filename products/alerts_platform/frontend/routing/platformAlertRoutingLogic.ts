function errorMessage(error: unknown): string {
    return error instanceof ApiError && error.detail ? error.detail : 'Try again in a moment.'
}

/** The form field a server-side validation error belongs to, if any. */
function fieldError<F extends string>(error: unknown, fieldByAttr: Record<string, F>): Partial<Record<F, string>> {
    if (error instanceof ApiError && error.attr && error.attr in fieldByAttr) {
        return { [fieldByAttr[error.attr]]: errorMessage(error) } as Partial<Record<F, string>>
    }
    return {}
}

