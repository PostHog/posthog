import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { Scene } from 'scenes/sceneTypes'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { Breadcrumb } from '~/types'

import { platformAlertsList } from './generated/api'
import { PaginatedPlatformAlertConfigurationListApi } from './generated/api.schemas'

export const PLATFORM_ALERTS_PAGE_SIZE = 50

export type PlatformAlertsTab = 'alerts' | 'routing'

export const PLATFORM_ALERTS_BREADCRUMB: Breadcrumb = {
    key: Scene.PlatformAlerts,
    name: 'Platform alerts',
    path: urls.platformAlerts(),
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface platformAlertsLogicValues {
    currentTeamId: number | null // teamLogic
    activeTab: PlatformAlertsTab
    breadcrumbs: Breadcrumb[]
    configurationsError: boolean
    configurationsPage: PaginatedPlatformAlertConfigurationListApi | null
    configurationsPageLoading: boolean
    page: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface platformAlertsLogicActions {
    loadCurrentTeamSuccess: (
        currentTeam: null | import('~/types').TeamPublicType,
        payload?: any
    ) => {
        currentTeam: null | import('~/types').TeamPublicType
        payload?: any
    } // teamLogic
    loadConfigurations: (_: void) => void
    loadConfigurationsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadConfigurationsSuccess: (
        configurationsPage: PaginatedPlatformAlertConfigurationListApi | null,
        payload?: void
    ) => {
        configurationsPage: PaginatedPlatformAlertConfigurationListApi | null
        payload?: void
    }
    setActiveTab: (activeTab: PlatformAlertsTab) => {
        activeTab: PlatformAlertsTab
    }
    setPage: (page: number) => {
        page: number
    }
}

export type platformAlertsLogicType = MakeLogicType<platformAlertsLogicValues, platformAlertsLogicActions>

export const platformAlertsLogic = kea<platformAlertsLogicType>([
    path(['products', 'alerts_platform', 'frontend', 'platformAlertsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [teamLogic, ['loadCurrentTeamSuccess']],
    })),
    actions({
        setPage: (page: number) => ({ page }),
        setActiveTab: (activeTab: PlatformAlertsTab) => ({ activeTab }),
    }),
    reducers({
        activeTab: ['alerts' as PlatformAlertsTab, { setActiveTab: (_, { activeTab }) => activeTab }],
        page: [
            1,
            {
                setPage: (_, { page }) => page,
                loadCurrentTeamSuccess: () => 1,
            },
        ],
    }),
    loaders(({ values }) => ({
        configurationsPage: [
            null as PaginatedPlatformAlertConfigurationListApi | null,
            {
                loadConfigurations: async (_: void, breakpoint) => {
                    if (!values.currentTeamId) {
                        return values.configurationsPage
                    }
                    const configurationsPage = await platformAlertsList(String(values.currentTeamId), {
                        limit: PLATFORM_ALERTS_PAGE_SIZE,
                        offset: (values.page - 1) * PLATFORM_ALERTS_PAGE_SIZE,
                    })
                    breakpoint()
                    return configurationsPage
                },
            },
        ],
    })),
    reducers({
        configurationsError: [
            false,
            {
                loadConfigurations: () => false,
                loadConfigurationsFailure: () => true,
            },
        ],
    }),
    selectors({
        breadcrumbs: [() => [], (): Breadcrumb[] => [PLATFORM_ALERTS_BREADCRUMB]],
    }),
    listeners(({ actions }) => ({
        setPage: () => {
            actions.loadConfigurations()
        },
        loadCurrentTeamSuccess: () => {
            actions.loadConfigurations()
        },
    })),
    actionToUrl(() => ({
        // pinned: the `tab` search param is a shareable link to the routing tab
        setActiveTab: ({ activeTab }) => [
            urls.platformAlerts(),
            { ...router.values.searchParams, tab: activeTab === 'alerts' ? undefined : activeTab },
            router.values.hashParams,
            { replace: true },
        ],
    })),
    urlToAction(({ actions, values }) => ({
        [urls.platformAlerts()]: (_, searchParams) => {
            const tab: PlatformAlertsTab = searchParams.tab === 'routing' ? 'routing' : 'alerts'
            if (tab !== values.activeTab) {
                actions.setActiveTab(tab)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadConfigurations()
    }),
])
