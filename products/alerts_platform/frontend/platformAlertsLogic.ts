export function reloadWhenSnoozeEnds(snoozeUntil: string, reload: () => void): () => () => void {
    return () => {
        let timer: ReturnType<typeof setTimeout>
        const arm = (): void => {
            const wait = Math.max(dayjs(snoozeUntil).diff(dayjs()), 0) + 1000
            timer = wait > MAX_TIMER_DELAY_MS ? setTimeout(arm, MAX_TIMER_DELAY_MS) : setTimeout(reload, wait)
        }
        arm()
        return () => clearTimeout(timer)
    }
}

function earliestSnoozeEnd(configurations: PlatformAlertConfigurationApi[]): string | null {
    const now = dayjs()
    return (
        configurations
            .flatMap((configuration) => [
                configuration.snooze_until,
                ...configuration.alerts.map((alert) => alert.snooze_until),
            ])
            .filter((snoozeUntil): snoozeUntil is string => !!snoozeUntil && dayjs(snoozeUntil).isAfter(now))
            .sort((a, b) => dayjs(a).diff(dayjs(b)))[0] ?? null
    )
}

export const platformAlertsLogic = kea<platformAlertsLogicType>([
    path(['products', 'alerts_platform', 'frontend', 'platformAlertsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [teamLogic, ['loadCurrentTeamSuccess']],
    })),
    actions({
        setPage: (page: number) => ({ page }),
        setActiveTab: (activeTab: PlatformAlertsTab) => ({ activeTab }),
        toggleExpanded: (id: string) => ({ id }),
        snoozeAlert: (configuration: PlatformAlertConfigurationApi, hours: number) => ({ configuration, hours }),
        unsnoozeAlert: (configuration: PlatformAlertConfigurationApi) => ({ configuration }),
        setAlertEnabled: (configuration: PlatformAlertConfigurationApi, enabled: boolean) => ({
            configuration,
            enabled,
        }),
        snoozeGroup: (
            configuration: PlatformAlertConfigurationApi,
            group: PlatformAlertApi,
            duration: GroupSnoozeDuration,
            hours: number
        ) => ({ configuration, group, duration, hours }),
        unsnoozeGroup: (configuration: PlatformAlertConfigurationApi, group: PlatformAlertApi) => ({
            configuration,
            group,
        }),
        setUpdatingAlertId: (id: string, updating: boolean) => ({ id, updating }),
    }),
    reducers({
        activeTab: ['alerts' as PlatformAlertsTab, { setActiveTab: (_, { activeTab }) => activeTab }],
        page: [
            1,
            {
                setPage: (_, { page }) => page,
                loadCurrentTeamSuccess: () => 1,
            },
        ],
        updatingAlertIds: [
            new Set<string>(),
            {
                setUpdatingAlertId: (state, { id, updating }) =>
                    updating ? new Set([...state, id]) : new Set([...state].filter((x) => x !== id)),
            },
        ],
        expandedIds: [
            [] as string[],
            {
                toggleExpanded: (state, { id }) =>
                    state.includes(id) ? state.filter((expandedId) => expandedId !== id) : [...state, id],
                loadCurrentTeamSuccess: () => [],
            },
        ],
    }),
    loaders(({ values }) => ({
        configurationsPage: [
            null as PaginatedPlatformAlertConfigurationListApi | null,
            {
                loadConfigurations: async (_: void, breakpoint) => {
                    if (!values.currentTeamId) {
                        return values.configurationsPage
                    }
                    const configurationsPage = await platformAlertsList(String(values.currentTeamId), {
                        limit: PLATFORM_ALERTS_PAGE_SIZE,
                        offset: (values.page - 1) * PLATFORM_ALERTS_PAGE_SIZE,
                    })
                    breakpoint()
                    return configurationsPage
                },
            },
        ],
    })),
    reducers({
        configurationsError: [
            false,
            {
                loadConfigurations: () => false,
                loadConfigurationsFailure: () => true,
            },
        ],
    }),
    selectors({
        breadcrumbs: [() => [], (): Breadcrumb[] => [PLATFORM_ALERTS_BREADCRUMB]],
        listRows: [
            (s) => [s.configurationsPage, s.expandedIds],
            (
                configurationsPage: platformAlertsLogicValues['configurationsPage'],
                expandedIds: platformAlertsLogicValues['expandedIds']
            ): PlatformAlertListRow[] => configurationListRows(configurationsPage?.results ?? [], expandedIds),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const reloadIfRowGone = (error: any): void => {
            if (error?.status === 404) {
                actions.loadConfigurations()
            }
        }
        const change = async (
            configuration: PlatformAlertConfigurationApi,
            request: (projectId: string) => Promise<unknown>,
            event: string,
            properties: Record<string, unknown>,
            done: string,
            updatingId: string = configuration.id
        ): Promise<void> => {
            actions.setUpdatingAlertId(updatingId, true)
            try {
                await request(String(values.currentTeamId))
                posthog.capture(event, {
                    configuration_id: configuration.id,
                    source_kind: configuration.source_kind,
                    ...properties,
                })
                lemonToast.success(done)
                actions.loadConfigurations()
            } catch (error: any) {
                lemonToast.error(error?.detail ?? "Couldn't update the alert. Try again.")
                reloadIfRowGone(error)
            } finally {
                actions.setUpdatingAlertId(updatingId, false)
            }
        }
        return {
            // pinned: analytics event names and properties. Renaming them breaks dashboards.
            snoozeAlert: ({ configuration, hours }) =>
                change(
                    configuration,
                    (projectId) =>
                        platformAlertsSnoozeCreate(projectId, configuration.id, {
                            snooze_until: dayjs().add(hours, 'hour').toISOString(),
                        }),
                    'platform alert snoozed',
                    { duration_hours: hours },
                    'Alert snoozed'
                ),
            unsnoozeAlert: ({ configuration }) =>
                change(
                    configuration,
                    (projectId) => platformAlertsSnoozeCreate(projectId, configuration.id, { snooze_until: null }),
                    'platform alert unsnoozed',
                    {},
                    'Alert unsnoozed'
                ),
            setAlertEnabled: ({ configuration, enabled }) =>
                change(
                    configuration,
                    (projectId) =>
                        platformAlertsPartialUpdate(projectId, configuration.id, {
                            source_kind: configuration.source_kind,
                            enabled,
                        }),
                    'platform alert enabled toggled',
                    { enabled },
                    enabled ? 'Alert enabled' : 'Alert disabled'
                ),
            snoozeGroup: ({ configuration, group, duration, hours }) =>
                change(
                    configuration,
                    (projectId) =>
                        platformAlertsSnoozeGroupCreate(projectId, configuration.id, {
                            grouping_key: group.grouping_key,
                            snooze_until: dayjs().add(hours, 'hour').toISOString(),
                        }),
                    'platform alert group snoozed',
                    { duration },
                    'Group snoozed',
                    group.id
                ),
            unsnoozeGroup: ({ configuration, group }) =>
                change(
                    configuration,
                    (projectId) =>
                        platformAlertsSnoozeGroupCreate(projectId, configuration.id, {
                            grouping_key: group.grouping_key,
                            snooze_until: null,
                        }),
                    'platform alert group unsnoozed',
                    { duration: null },
                    'Group unsnoozed',
                    group.id
                ),
            setPage: () => {
                actions.loadConfigurations()
            },
            loadCurrentTeamSuccess: () => {
                actions.loadConfigurations()
            },
            loadConfigurationsSuccess: ({ configurationsPage }) => {
                const snoozeUntil = earliestSnoozeEnd(configurationsPage?.results ?? [])
                if (!snoozeUntil) {
                    cache.disposables.dispose('reloadAtSnoozeEnd')
                    return
                }
                cache.disposables.add(
                    reloadWhenSnoozeEnds(snoozeUntil, () => actions.loadConfigurations()),
                    'reloadAtSnoozeEnd'
                )
            },
        }
    }),
    actionToUrl(() => ({
        // pinned: the `tab` search param is a shareable link to the routing tab
        setActiveTab: ({ activeTab }) => [
            urls.platformAlerts(),
            { ...router.values.searchParams, tab: activeTab === 'alerts' ? undefined : activeTab },
            router.values.hashParams,
            { replace: true },
        ],
    })),
    urlToAction(({ actions, values }) => ({
        [urls.platformAlerts()]: (_, searchParams) => {
            const tab: PlatformAlertsTab = searchParams.tab === 'routing' ? 'routing' : 'alerts'
            if (tab !== values.activeTab) {
                actions.setActiveTab(tab)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadConfigurations()
    }),
])
