const PKCE_CHALLENGE = /^[A-Za-z0-9_-]{43}$/

export interface CliRequest {
    challenge: string
    port: number
    state: string
}

export function parseCliRequest(searchParams: Record<string, any>): CliRequest | null {
    const challenge = String(searchParams.cli_challenge ?? '')
    const port = Number(searchParams.cli_port)
    const state = String(searchParams.cli_state ?? '')
    if (!PKCE_CHALLENGE.test(challenge) || !Number.isInteger(port) || port < 1024 || port > 65535 || !state) {
        return null
    }
    return { challenge, port, state }
}

const HOUR = 60 * 60
const DAY = 24 * HOUR
export const DURATION_PRESETS: { seconds: number; label: string }[] = [
    { seconds: HOUR, label: '1 hour' },
    { seconds: 8 * HOUR, label: '8 hours' },
    { seconds: DAY, label: '1 day' },
    { seconds: 3 * DAY, label: '3 days' },
    { seconds: 7 * DAY, label: '7 days' },
]

export function formatDuration(seconds: number): string {
    const preset = DURATION_PRESETS.find((p) => p.seconds === seconds)
    if (preset) {
        return preset.label
    }
    return seconds % DAY === 0 ? `${seconds / DAY} days` : `${Math.round(seconds / HOUR)} hours`
}

/** hogli prefills the picker; the staff member can change it before approving. */
export function parseCliPick(searchParams: Record<string, any>): { capUsd: number | null; ttlSeconds: number | null } {
    const cap = Number(searchParams.cli_cap_usd)
    const ttl = Number(searchParams.cli_ttl_seconds)
    return {
        capUsd: searchParams.cli_cap_usd != null && Number.isFinite(cap) && cap > 0 ? cap : null,
        ttlSeconds: searchParams.cli_ttl_seconds != null && Number.isInteger(ttl) && ttl > 0 ? ttl : null,
    }
}

export function pickError(
    usage: DevTokenUsageApi | null,
    capUsd: number | null,
    ttlSeconds: number | null
): string | null {
    if (!usage) {
        return null
    }
    const min = Number(usage.token_cap_min_usd)
    const max = Number(usage.token_cap_usd)
    if (capUsd === null || !Number.isFinite(capUsd) || capUsd < min || capUsd > max) {
        return `Pick an amount between $${min} and $${max}.`
    }
    if (Math.round(capUsd * 100) !== capUsd * 100) {
        return 'Pick an amount in whole cents.'
    }
    if (ttlSeconds === null || ttlSeconds < usage.ttl_min_seconds || ttlSeconds > usage.ttl_max_seconds) {
        return `Pick a duration between ${formatDuration(usage.ttl_min_seconds)} and ${formatDuration(usage.ttl_max_seconds)}.`
    }
    return null
}

export function cliCallbackUrl(request: CliRequest, code: string): string {
    const params = new URLSearchParams({ code, state: request.state })
    return `http://127.0.0.1:${request.port}/callback?${params.toString()}`
}

function errorDetail(error: any): string {
    return error?.detail || error?.message || "Couldn't reach PostHog. Refresh the page and try again."
}

