export const devModeLogic = kea<devModeLogicType>([
    path(['products', 'ai_gateway', 'frontend', 'logics', 'devModeLogic']),
    actions({
        setCliRequest: (cliRequest: CliRequest | null) => ({ cliRequest }),
        authorizeCli: true,
        dismissCliRequest: true,
        revokeToken: (id: string | null) => ({ id }),
        revokeTokenFinished: true,
    }),
    reducers({
        cliRequest: [
            null as CliRequest | null,
            { setCliRequest: (_, { cliRequest }) => cliRequest, dismissCliRequest: () => null },
        ],
        revoking: [
            null as { id: string | null } | null,
            { revokeToken: (_, { id }) => ({ id }), revokeTokenFinished: () => null },
        ],
        refusal: [
            null as string | null,
            {
                loadUsageFailure: (_, { error }) => error ?? null,
                loadUsageSuccess: () => null,
            },
        ],
    }),
    loaders(({ values }) => ({
        usage: [
            null as DevTokenUsageApi | null,
            {
                loadUsage: async () => {
                    try {
                        return await aiGatewayDevTokensUsageRetrieve()
                    } catch (error: any) {
                        throw new Error(errorDetail(error))
                    }
                },
            },
        ],
        minted: [
            null as MintedDevTokenApi | null,
            {
                mint: async () => {
                    try {
                        return await aiGatewayDevTokensCreate()
                    } catch (error: any) {
                        lemonToast.error(errorDetail(error))
                        return values.minted
                    }
                },
                clearMinted: () => null,
            },
        ],
    })),
    selectors({
        remainingUsd: [
            (s) => [s.usage],
            (usage: DevTokenUsageApi | null): number | null =>
                usage ? Math.max(0, Number(usage.daily_cap_usd) - Number(usage.used_usd)) : null,
        ],
        liveTokenCount: [
            (s) => [s.usage],
            (usage: DevTokenUsageApi | null): number =>
                usage?.tokens.filter((token) => token.status === 'live').length ?? 0,
        ],
        canMint: [
            (s) => [s.usage, s.remainingUsd],
            (usage: DevTokenUsageApi | null, remainingUsd: number | null): boolean =>
                !!usage && remainingUsd !== null && remainingUsd >= Number(usage.token_cap_usd),
        ],
    }),
    listeners(({ actions, values }) => ({
        mintSuccess: () => actions.loadUsage(),
        revokeToken: async ({ id }) => {
            try {
                const { revoked_count } = await aiGatewayDevTokensRevokeCreate({ id })
                lemonToast.success(revoked_count === 1 ? 'Token revoked' : `${revoked_count} tokens revoked`)
                if (values.minted && (id === null || values.minted.id === id)) {
                    actions.clearMinted()
                }
            } catch (error: any) {
                lemonToast.error(errorDetail(error))
            }
            actions.revokeTokenFinished()
            actions.loadUsage()
        },
        authorizeCli: async () => {
            const request = values.cliRequest
            if (!request) {
                return
            }
            try {
                const { code } = await aiGatewayDevTokensCliAuthorizeCreate({ code_challenge: request.challenge })
                actions.dismissCliRequest()
                window.location.href = cliCallbackUrl(request, code)
            } catch (error: any) {
                lemonToast.error(errorDetail(error))
            }
        },
        dismissCliRequest: () => {
            const { cli_challenge, cli_port, cli_state, ...rest } = router.values.searchParams
            router.actions.replace(router.values.location.pathname, rest, router.values.hashParams)
        },
    })),
    urlToAction(({ actions }) => ({
        '*': (_, searchParams) => {
            if (searchParams.cli_challenge) {
                actions.setCliRequest(parseCliRequest(searchParams))
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadUsage()
    }),
])
