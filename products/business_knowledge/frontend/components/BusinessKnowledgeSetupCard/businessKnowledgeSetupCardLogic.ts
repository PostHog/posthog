export type businessKnowledgeSetupCardLogicType = MakeLogicType<
    businessKnowledgeSetupCardLogicValues,
    businessKnowledgeSetupCardLogicActions
>

export const businessKnowledgeSetupCardLogic = kea<businessKnowledgeSetupCardLogicType>([
    path([
        'products',
        'business_knowledge',
        'frontend',
        'components',
        'BusinessKnowledgeSetupCard',
        'businessKnowledgeSetupCardLogic',
    ]),
    connect(() => ({
        actions: [
            businessKnowledgeLogic,
            ['openCreateModal', 'setCreateTab', 'setUrlSourceValue', 'setUrlSourceValues', 'submitUrlSource'],
            productSetupStatusLogic({ productKey: ProductKey.BUSINESS_KNOWLEDGE }),
            ['reportSetupInteraction'],
        ],
        values: [businessKnowledgeLogic, ['urlSource']],
    })),
    actions({
        submitWebsite: (mode: ProductEmptyStateMode, preview: boolean) => ({ mode, preview }),
        pickSource: (source: BusinessKnowledgeSetupSource, mode: ProductEmptyStateMode, preview: boolean) => ({
            source,
            mode,
            preview,
        }),
    }),
    loaders({
        suggestedWebsite: [
            null as string | null,
            {
                loadSuggestedWebsite: async () => {
                    const query = hogql`
                        select properties.$host as host, count() as views
                        from events
                        where event = '$pageview'
                            and timestamp >= now() - interval 3 day
                            and timestamp <= now()
                            and properties.$host is not null
                        group by host
                        order by views desc
                        limit 10`
                    try {
                        const response = await api.queryHogQL<[string, number][]>(query, {
                            scene: 'BusinessKnowledge',
                            productKey: 'business_knowledge',
                            name: 'business_knowledge_setup_website_suggestion',
                        })
                        return pickWebsiteFromHosts((response.results ?? []).map(([host]) => host))
                    } catch {
                        return null
                    }
                },
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        loadSuggestedWebsiteSuccess: ({ suggestedWebsite }) => {
            // The query can finish after the person starts to type, and their text must stay.
            if (suggestedWebsite && !values.urlSource.url.trim()) {
                actions.setUrlSourceValue('url', suggestedWebsite)
            }
        },
        submitWebsite: ({ mode, preview }) => {
            const url = normalizeWebsiteUrl(values.urlSource.url)
            actions.reportSetupInteraction('website submitted', mode, null, preview)
            if (!preview) {
                // pinned: analytics event name. Renaming it breaks insights built on it.
                posthog.capture('business knowledge setup website submitted', {
                    mode,
                    suggested: values.suggestedWebsite !== null,
                    used_suggestion: url === values.suggestedWebsite,
                })
            }
            actions.setUrlSourceValues({
                url,
                name: websiteSourceName(url) ?? values.urlSource.name,
                crawl_mode: 'same_origin',
            })
            actions.submitUrlSource()
        },
        pickSource: ({ source, mode, preview }) => {
            actions.reportSetupInteraction('source picked', mode, null, preview)
            if (!preview) {
                // pinned: analytics event name. Renaming it breaks insights built on it.
                posthog.capture('business knowledge setup source picked', { source, mode })
            }
            const createTab = CREATE_TAB_BY_SOURCE[source]
            if (createTab) {
                actions.openCreateModal()
                actions.setCreateTab(createTab)
                return
            }
            router.actions.push(
                urls.businessKnowledgeSettings(),
                {},
                { selectedSetting: SETTING_BY_SOURCE[source as keyof typeof SETTING_BY_SOURCE] }
            )
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSuggestedWebsite()
    }),
])
