import { MakeLogicType, actions, connect, kea, listeners, path } from 'kea'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { productSetupStatusLogic } from 'lib/components/ProductEmptyState/productSetupStatusLogic'
import type { ProductEmptyStateMode } from 'lib/components/ProductEmptyState/types'
import { urls } from 'scenes/urls'

import { ProductKey } from '~/queries/schema/schema-general'

import { type CreateTab, businessKnowledgeLogic } from '../../scenes/sources/businessKnowledgeLogic'

export type BusinessKnowledgeSetupSource = 'url' | 'file' | 'text' | 'github' | 'support'

// pinned: setting ids from the settings map. The settings scene reads them from the `selectedSetting` hash.
const SETTING_BY_SOURCE = {
    github: 'business-knowledge-github-repos',
    support: 'business-knowledge-learn-from-support',
} as const

const CREATE_TAB_BY_SOURCE: Partial<Record<BusinessKnowledgeSetupSource, CreateTab>> = {
    url: 'url',
    file: 'file',
    text: 'text',
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface businessKnowledgeSetupCardLogicActions {
    reportSetupInteraction: (action: string, mode: ProductEmptyStateMode, route?: null, preview?: boolean) => void // productSetupStatusLogic
    openCreateModal: () => void // businessKnowledgeLogic
    setCreateTab: (tab: CreateTab) => void // businessKnowledgeLogic
    pickSource: (
        source: BusinessKnowledgeSetupSource,
        mode: ProductEmptyStateMode,
        preview: boolean
    ) => {
        source: BusinessKnowledgeSetupSource
        mode: ProductEmptyStateMode
        preview: boolean
    }
}

export type businessKnowledgeSetupCardLogicType = MakeLogicType<
    Record<string, never>,
    businessKnowledgeSetupCardLogicActions
>

export const businessKnowledgeSetupCardLogic = kea<businessKnowledgeSetupCardLogicType>([
    path([
        'products',
        'business_knowledge',
        'frontend',
        'components',
        'BusinessKnowledgeSetupCard',
        'businessKnowledgeSetupCardLogic',
    ]),
    connect(() => ({
        actions: [
            businessKnowledgeLogic,
            ['openCreateModal', 'setCreateTab'],
            productSetupStatusLogic({ productKey: ProductKey.BUSINESS_KNOWLEDGE }),
            ['reportSetupInteraction'],
        ],
    })),
    actions({
        pickSource: (source: BusinessKnowledgeSetupSource, mode: ProductEmptyStateMode, preview: boolean) => ({
            source,
            mode,
            preview,
        }),
    }),
    listeners(({ actions }) => ({
        pickSource: ({ source, mode, preview }) => {
            actions.reportSetupInteraction('source picked', mode, null, preview)
            if (!preview) {
                // pinned: analytics event name. Renaming it breaks insights built on it.
                posthog.capture('business knowledge setup source picked', { source, mode })
            }
            const createTab = CREATE_TAB_BY_SOURCE[source]
            if (createTab) {
                actions.openCreateModal()
                actions.setCreateTab(createTab)
                return
            }
            router.actions.push(
                urls.businessKnowledgeSettings(),
                {},
                { selectedSetting: SETTING_BY_SOURCE[source as keyof typeof SETTING_BY_SOURCE] }
            )
        },
    })),
])
