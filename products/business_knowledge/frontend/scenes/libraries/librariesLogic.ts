import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import type { TeamType } from '~/types'

import type { TeamPublicType } from '../../../../../frontend/src/types'
import { createLibrary, listLibraries } from '../../api'
import { businessKnowledgeKeysList } from '../../generated/api'
import type { KnowledgeKeyApi, KnowledgeLibraryApi } from '../../generated/api.schemas'

export const ALL_KNOWLEDGE_ROW_ID = 'all'

export interface LibraryTableRow {
    id: string
    name: string
    /** Null for the row that stands for all business knowledge. */
    library: KnowledgeLibraryApi | null
    /** Null when the keys are not loaded, for example in a child environment. */
    keyCount: number | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface librariesLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    canListKeys: boolean
    creating: boolean
    isCreateOpen: boolean
    keys: KnowledgeKeyApi[] | null
    keysLoading: boolean
    libraries: KnowledgeLibraryApi[] | null
    librariesLoading: boolean
    rows: LibraryTableRow[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface librariesLogicActions {
    closeCreate: () => {
        value: true
    }
    createLibrary: (name: string) => {
        name: string
    }
    finishCreate: () => {
        value: true
    }
    loadKeys: () => any
    loadKeysFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadKeysSuccess: (
        keys: KnowledgeKeyApi[] | null,
        payload?: any
    ) => {
        keys: KnowledgeKeyApi[] | null
        payload?: any
    }
    loadLibraries: () => any
    loadLibrariesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadLibrariesSuccess: (
        libraries: KnowledgeLibraryApi[],
        payload?: any
    ) => {
        libraries: KnowledgeLibraryApi[]
        payload?: any
    }
    openCreate: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface librariesLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        canListKeys: (currentTeam: TeamPublicType | TeamType | null) => boolean
        rows: (libraries: KnowledgeLibraryApi[] | null, keys: KnowledgeKeyApi[] | null) => LibraryTableRow[]
    }
}

export type librariesLogicType = MakeLogicType<
    librariesLogicValues,
    librariesLogicActions,
    Record<string, any>,
    librariesLogicMeta
>

export const librariesLogic = kea<librariesLogicType>([
    path(['products', 'business_knowledge', 'frontend', 'libraries', 'librariesLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeam']] })),
    actions({
        openCreate: true,
        closeCreate: true,
        createLibrary: (name: string) => ({ name }),
        finishCreate: true,
    }),
    loaders(({ values }) => ({
        libraries: [
            null as KnowledgeLibraryApi[] | null,
            {
                loadLibraries: async () => await listLibraries(),
            },
        ],
        keys: [
            null as KnowledgeKeyApi[] | null,
            {
                loadKeys: async () => {
                    // The key counts are an extra column. A failure hides the column and must not toast.
                    try {
                        return await businessKnowledgeKeysList(String(values.currentTeam?.id))
                    } catch {
                        return null
                    }
                },
            },
        ],
    })),
    reducers({
        isCreateOpen: [
            false,
            {
                openCreate: () => true,
                closeCreate: () => false,
            },
        ],
        creating: [
            false,
            {
                createLibrary: () => true,
                finishCreate: () => false,
            },
        ],
    }),
    selectors({
        // The keys endpoint refuses a child environment, because business knowledge belongs to the project.
        canListKeys: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | null): boolean => !!currentTeam && currentTeam.id === currentTeam.project_id,
        ],
        rows: [
            (s) => [s.libraries, s.keys],
            (libraries: KnowledgeLibraryApi[] | null, keys: KnowledgeKeyApi[] | null): LibraryTableRow[] => {
                const libraryRows = (libraries ?? []).map((library) => ({
                    id: library.id,
                    name: library.name,
                    library,
                    keyCount: keys ? keys.filter((key) => key.library_id === library.id).length : null,
                }))
                // With no libraries the table shows its empty state, which says how to start.
                if (!keys || libraryRows.length === 0) {
                    return libraryRows
                }
                return [
                    {
                        id: ALL_KNOWLEDGE_ROW_ID,
                        name: 'All business knowledge',
                        library: null,
                        keyCount: keys.filter((key) => !key.is_limited).length,
                    },
                    ...libraryRows,
                ]
            },
        ],
    }),
    listeners(({ actions, cache }) => ({
        createLibrary: async ({ name }) => {
            try {
                const library = await createLibrary(name)
                // The person left the tab while the request ran. Do not pull them to the new library.
                if (cache.disposables.isDisposed) {
                    return
                }
                // pinned: analytics event name. Renaming it breaks insights built on it.
                posthog.capture('business knowledge library created')
                actions.closeCreate()
                router.actions.push(urls.businessKnowledgeLibrary(library.id))
            } catch (error: any) {
                lemonToast.error(error?.detail || error?.data?.name?.[0] || 'Could not create the library.')
            } finally {
                actions.finishCreate()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        actions.loadLibraries()
        if (values.canListKeys) {
            actions.loadKeys()
        }
    }),
])
