export const knowledgeSourceLogic: LogicWrapper<knowledgeSourceLogicType> = kea<knowledgeSourceLogicType>([
    props({} as KnowledgeSourceLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'business_knowledge', 'knowledgeSourceLogic', key]),
    actions({
        markSourceNotFound: true,
        deleteSource: true,
        deleteSourceDone: true,
        refreshSource: true,
        refreshSourceDone: true,
    }),
    reducers({
        sourceNotFound: [
            false,
            {
                loadSource: () => false,
                markSourceNotFound: () => true,
            },
        ],
        isDeleting: [
            false,
            {
                deleteSource: () => true,
                deleteSourceDone: () => false,
            },
        ],
        isRefreshing: [
            false,
            {
                refreshSource: () => true,
                refreshSourceDone: () => false,
            },
        ],
        sourceTextFailed: [
            false,
            {
                loadSourceText: () => false,
                loadSourceTextSuccess: () => false,
                loadSourceTextFailure: () => true,
            },
        ],
    }),
    loaders(({ actions, props }) => ({
        source: [
            null as KnowledgeSource | null,
            {
                loadSource: async () => {
                    try {
                        return await getSource(props.id)
                    } catch (error: unknown) {
                        // Catch 404 here so initKea does not toast. The scene renders NotFound.
                        if ((error as { status?: number } | null)?.status === 404) {
                            actions.markSourceNotFound()
                            return null
                        }
                        throw error
                    }
                },
            },
        ],
        sourceText: [
            { id: '', text: '' } as { id: string; text: string },
            {
                loadSourceText: async () => {
                    return await getSourceText(props.id)
                },
            },
        ],
    })),
    forms(({ actions, values, props }) => ({
        editSource: {
            defaults: { name: '', text: '', always_include: false } as TextSourceFormValues,
            errors: (vals: TextSourceFormValues) => {
                if (values.source?.source_type === 'text' && hasLoadedSourceText(values.source, values.sourceText)) {
                    return validateText(vals)
                }
                return {
                    name: !vals.name.trim() ? 'Give the source a short name' : undefined,
                }
            },
            submit: async ({ name, text, always_include }: TextSourceFormValues) => {
                const current = values.source
                if (!current) {
                    return
                }
                const includeText = current.source_type === 'text' && hasLoadedSourceText(current, values.sourceText)
                const payload: UpdateSourcePayload = { name, always_include, ...(includeText && { text }) }
                try {
                    const updated = await updateSource(props.id, payload)
                    const msg = includeText
                        ? `"${updated.name}" re-indexed into ${updated.chunk_count} chunks`
                        : `"${updated.name}" renamed`
                    lemonToast.success(msg)
                    actions.loadSource()
                } catch (error: any) {
                    lemonToast.error(
                        error?.detail ||
                            error?.data?.detail ||
                            'Could not save the changes. Check the error and try again.'
                    )
                    throw error
                }
            },
        },
        editUrlSource: {
            defaults: DEFAULT_URL_SOURCE_FORM,
            errors: validateUrl,
            submit: async (vals: UrlSourceFormValues) => {
                const current = values.source
                if (!current) {
                    return
                }
                const editIncludeGlobs = splitGlobs(vals.include_globs)
                const payload: UpdateSourcePayload = {
                    name: vals.name,
                    url: vals.url,
                    crawl_mode: vals.crawl_mode,
                    refresh_interval: vals.refresh_interval,
                    always_include: vals.always_include,
                    ...(vals.crawl_mode !== 'single' && {
                        ...(editIncludeGlobs.length > 0 && { include_globs: editIncludeGlobs }),
                        exclude_globs: splitGlobs(vals.exclude_globs),
                        max_pages: vals.max_pages,
                        max_depth: vals.max_depth,
                    }),
                }
                try {
                    const updated = await updateSource(props.id, payload)
                    lemonToast.success(`"${updated.name}" updated`)
                    actions.loadSource()
                } catch (error: any) {
                    lemonToast.error(
                        error?.detail ||
                            error?.data?.url?.[0] ||
                            error?.data?.detail ||
                            'Could not save the changes. Check the error and try again.'
                    )
                    throw error
                }
            },
        },
    })),
    listeners(({ actions, values, props, cache }) => ({
        loadSourceSuccess: ({ source }) => {
            if (!source) {
                cache.disposables.dispose('pollProcessing')
                return
            }
            // Hydrate once. Later polls must not wipe in-progress edits, and a text
            // save must not restore the stale sourceText loader value.
            if (!cache.formHydrated) {
                if (source.source_type === 'url') {
                    actions.setEditUrlSourceValues(editUrlSourceValuesFromSource(source))
                } else {
                    const textReady = hasLoadedSourceText(source, values.sourceText)
                    actions.setEditSourceValues({
                        name: source.name,
                        text: textReady ? values.sourceText.text : '',
                        always_include: source.always_include ?? false,
                    })
                    if (!textReady) {
                        actions.loadSourceText()
                    }
                }
                cache.formHydrated = true
            }
            const delayMs = sourcePollDelayMs(source)
            if (delayMs === null) {
                cache.disposables.dispose('pollProcessing')
            } else {
                cache.disposables.add(() => {
                    const id = setTimeout(() => actions.loadSource(), delayMs)
                    return () => clearTimeout(id)
                }, 'pollProcessing')
            }
        },
        loadSourceTextSuccess: ({ sourceText }) => {
            if (values.source && values.source.id === sourceText.id) {
                actions.setEditSourceValue('text', sourceText.text)
            }
        },
        deleteSource: async () => {
            try {
                await deleteSource(props.id)
                lemonToast.success('Knowledge source deleted')
                router.actions.push(urls.businessKnowledge())
            } catch (error: any) {
                lemonToast.error(error?.detail || 'Could not delete the source.')
            } finally {
                actions.deleteSourceDone()
            }
        },
        refreshSource: async () => {
            try {
                const updated = await refreshSource(props.id)
                if (updated.last_refresh_status === 'not_modified') {
                    lemonToast.info(`"${updated.name}" is already up to date`)
                } else {
                    lemonToast.success(`"${updated.name}" refreshed`)
                }
                actions.loadSource()
            } catch (error: any) {
                lemonToast.error(
                    error?.detail || error?.data?.detail || error?.data?.url?.[0] || 'Could not refresh the source.'
                )
            } finally {
                actions.refreshSourceDone()
            }
        },
    })),
    selectors({
        breadcrumbs: [
            (s) => [s.source],
            (source: KnowledgeSource | null): Breadcrumb[] => [
                {
                    key: Scene.BusinessKnowledge,
                    name: 'Business knowledge',
                    path: urls.businessKnowledge(),
                    iconType: 'conversations',
                },
                {
                    key: Scene.BusinessKnowledgeSource,
                    name: source?.name ?? 'Knowledge source',
                    iconType: 'conversations',
                },
            ],
        ],
        isSourceTextReady: [
            (s) => [s.source, s.sourceText, s.sourceTextFailed],
            (
                source: KnowledgeSource | null,
                sourceText: { id: string; text: string },
                sourceTextFailed: boolean
            ): boolean => hasLoadedSourceText(source, sourceText) || sourceTextFailed,
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadSource()
    }),
])
