const POLL_MS = 2000
const LIST_POLL_MS = 5000
// Matches MAX_OPEN_RUNS_PER_OWNER in backend/sandbox.py. The server still enforces the limit.
const MAX_OPEN_ANSWERS = 3

function errorDetail(error: unknown, fallback: string): string {
    if (error instanceof ApiError && error.detail) {
        return error.detail
    }
    return fallback
}

function isTerminal(run: SandboxRunApi | null): boolean {
    return run?.status === 'completed' || run?.status === 'failed' || run?.status === 'cancelled'
}

function hasOpenTurn(chat: PlaygroundChatApi | null): boolean {
    return Boolean(chat?.turns.some((turn) => turn.run !== null && !isTerminal(turn.run)))
}

