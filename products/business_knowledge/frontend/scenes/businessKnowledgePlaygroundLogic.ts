export const businessKnowledgePlaygroundLogic = kea<businessKnowledgePlaygroundLogicType>([
    path(['products', 'business_knowledge', 'frontend', 'scenes', 'businessKnowledgePlaygroundLogic']),
    actions({
        setQuestion: (question: string) => ({ question }),
        setAsking: (asking: boolean) => ({ asking }),
        setAskError: (askError: string | null) => ({ askError }),
        setChatError: (chatError: string | null) => ({ chatError }),
        setChatLoading: (chatLoading: boolean) => ({ chatLoading }),
        setChatId: (chatId: string | null) => ({ chatId }),
        openChat: (chatId: string | null) => ({ chatId }),
        newChat: true,
        deleteChat: (chatId: string) => ({ chatId }),
        setDeletingChatId: (deletingChatId: string | null) => ({ deletingChatId }),
        ask: true,
        chatLoaded: (chat: PlaygroundChatApi) => ({ chat }),
        startPolling: true,
        poll: true,
        pollFailed: (error: string) => ({ error }),
    }),
    loaders(() => ({
        chats: [
            [] as PlaygroundChatListApi[],
            {
                loadChats: async (): Promise<PlaygroundChatListApi[]> => listPlaygroundChats(),
            },
        ],
    })),
    reducers({
        question: [
            '',
            {
                setQuestion: (_, { question }) => question,
                openChat: () => '',
            },
        ],
        asking: [
            false,
            {
                setAsking: (_, { asking }) => asking,
            },
        ],
        askError: [
            null as string | null,
            {
                setAskError: (_, { askError }) => askError,
                openChat: () => null,
            },
        ],
        chatId: [
            null as string | null,
            {
                openChat: (_, { chatId }) => chatId,
                setChatId: (_, { chatId }) => chatId,
            },
        ],
        chat: [
            null as PlaygroundChatApi | null,
            {
                openChat: () => null,
                chatLoaded: (_, { chat }) => chat,
            },
        ],
        chatError: [
            null as string | null,
            {
                setChatError: (_, { chatError }) => chatError,
                openChat: () => null,
                chatLoaded: () => null,
                pollFailed: (_, { error }) => error,
            },
        ],
        chatLoading: [
            false,
            {
                setChatLoading: (_, { chatLoading }) => chatLoading,
                openChat: (_, { chatId }) => Boolean(chatId),
                chatLoaded: () => false,
            },
        ],
        deletingChatId: [
            null as string | null,
            {
                setDeletingChatId: (_, { deletingChatId }) => deletingChatId,
            },
        ],
    }),
    selectors({
        chatHasOpenTurn: [(s) => [s.chat], (chat: PlaygroundChatApi | null): boolean => hasOpenTurn(chat)],
        askDisabled: [
            (s) => [s.asking, s.chatHasOpenTurn, s.question],
            (asking: boolean, chatHasOpenTurn: boolean, question: string): boolean =>
                asking || chatHasOpenTurn || question.trim().length === 0,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openChat: async ({ chatId }) => {
            cache.disposables.dispose('playgroundPoll')
            actions.setAsking(false)
            if (!chatId) {
                return
            }
            try {
                const chat = await getPlaygroundChat(chatId)
                if (cache.disposables.isDisposed || values.chatId !== chatId) {
                    return
                }
                actions.chatLoaded(chat)
                if (hasOpenTurn(chat)) {
                    actions.setAsking(true)
                    actions.startPolling()
                }
            } catch (error) {
                if (cache.disposables.isDisposed || values.chatId !== chatId) {
                    return
                }
                actions.setChatLoading(false)
                actions.setChatError(errorDetail(error, "Couldn't load this chat. Try again."))
            }
        },
        newChat: () => {
            if (router.values.location.pathname === urls.currentProject(urls.businessKnowledgePlayground())) {
                actions.openChat(null)
                return
            }
            router.actions.push(urls.businessKnowledgePlayground())
        },
        deleteChat: async ({ chatId }) => {
            if (values.deletingChatId) {
                return
            }
            actions.setDeletingChatId(chatId)
            try {
                await deletePlaygroundChat(chatId)
                if (cache.disposables.isDisposed) {
                    return
                }
                actions.loadChats()
                if (values.chatId === chatId) {
                    actions.newChat()
                }
            } catch (error) {
                if (cache.disposables.isDisposed) {
                    return
                }
                actions.setChatError(errorDetail(error, "Couldn't delete this chat. Try again."))
            } finally {
                if (!cache.disposables.isDisposed) {
                    actions.setDeletingChatId(null)
                }
            }
        },
        ask: async () => {
            if (values.asking || values.chatHasOpenTurn) {
                return
            }
            const question = values.question.trim()
            if (!question) {
                return
            }
            actions.setAsking(true)
            actions.setAskError(null)
            try {
                let chatId = values.chatId
                if (!chatId) {
                    const created = await createPlaygroundChat()
                    chatId = created.id
                    actions.setChatId(chatId)
                    router.actions.replace(urls.businessKnowledgePlayground(chatId))
                    actions.loadChats()
                }
                const chat = await askPlaygroundChat(chatId, question)
                if (cache.disposables.isDisposed) {
                    return
                }
                actions.setQuestion('')
                actions.chatLoaded(chat)
                actions.loadChats()
                if (hasOpenTurn(chat)) {
                    actions.startPolling()
                }
            } catch (error) {
                if (cache.disposables.isDisposed) {
                    return
                }
                actions.setAskError(errorDetail(error, "Couldn't start the answer. Try again."))
                actions.setAsking(false)
            }
        },
        startPolling: () => {
            cache.disposables.add(() => {
                const id = window.setInterval(() => {
                    actions.poll()
                }, POLL_MS)
                return () => window.clearInterval(id)
            }, 'playgroundPoll')
            actions.poll()
        },
        poll: async () => {
            const chatId = values.chatId
            if (!chatId) {
                return
            }
            try {
                const chat = await getPlaygroundChat(chatId)
                if (cache.disposables.isDisposed || values.chatId !== chatId) {
                    return
                }
                actions.chatLoaded(chat)
            } catch (error) {
                if (cache.disposables.isDisposed || values.chatId !== chatId) {
                    return
                }
                if (error instanceof ApiError && error.status === 404) {
                    actions.pollFailed(errorDetail(error, "Couldn't check the answer. Try again."))
                    return
                }
                actions.setChatError(errorDetail(error, "Couldn't check the answer. Try again."))
            }
        },
        chatLoaded: ({ chat }) => {
            if (!hasOpenTurn(chat)) {
                cache.disposables.dispose('playgroundPoll')
                actions.setAsking(false)
            }
        },
        pollFailed: () => {
            cache.disposables.dispose('playgroundPoll')
            actions.setAsking(false)
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.businessKnowledgePlayground()]: () => {
            if (values.chatId !== null) {
                actions.openChat(null)
            }
        },
        [`${urls.businessKnowledgePlayground()}/:chatId`]: ({ chatId }) => {
            if (chatId && chatId !== values.chatId) {
                actions.openChat(chatId)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadChats()
    }),
])
