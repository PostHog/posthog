export const businessKnowledgePlaygroundLogic = kea<businessKnowledgePlaygroundLogicType>([
    path(['products', 'business_knowledge', 'frontend', 'scenes', 'businessKnowledgePlaygroundLogic']),
    actions({
        setQuestion: (question: string) => ({ question }),
        setPendingQuestion: (pendingQuestion: string | null) => ({ pendingQuestion }),
        setChatSearch: (chatSearch: string) => ({ chatSearch }),
        setAsking: (asking: boolean) => ({ asking }),
        setAskError: (askError: string | null) => ({ askError }),
        setChatError: (chatError: string | null) => ({ chatError }),
        setChatLoading: (chatLoading: boolean) => ({ chatLoading }),
        setChatId: (chatId: string | null) => ({ chatId }),
        openChat: (chatId: string | null) => ({ chatId }),
        newChat: true,
        loadMoreChats: true,
        appendOlderChats: (chats: PlaygroundChatListApi[]) => ({ chats }),
        clearOlderChats: true,
        removeOlderChat: (chatId: string) => ({ chatId }),
        setNextChatsOffset: (offset: number | null) => ({ offset }),
        setLoadingMoreChats: (loading: boolean) => ({ loading }),
        setMoreChatsError: (error: string | null) => ({ error }),
        deleteChat: (chatId: string) => ({ chatId }),
        setDeletingChatId: (deletingChatId: string | null) => ({ deletingChatId }),
        ask: true,
        chatLoaded: (chat: PlaygroundChatApi) => ({ chat }),
        startPolling: true,
        poll: true,
        pollFailed: (error: string) => ({ error }),
    }),
    loaders(({ actions, values }) => ({
        chats: [
            [] as PlaygroundChatListApi[],
            {
                loadChats: async (): Promise<PlaygroundChatListApi[]> => {
                    const page = await listPlaygroundChats()
                    if (!page.next) {
                        actions.clearOlderChats()
                        actions.setNextChatsOffset(null)
                    } else {
                        const loadedIds = new Set([...page.results, ...values.olderChats].map((chat) => chat.id))
                        actions.setNextChatsOffset(loadedIds.size)
                    }
                    return page.results
                },
            },
        ],
    })),
    reducers({
        olderChats: [
            [] as PlaygroundChatListApi[],
            {
                appendOlderChats: (state, { chats }) => {
                    const ids = new Set(state.map((chat) => chat.id))
                    return [...state, ...chats.filter((chat) => !ids.has(chat.id))]
                },
                clearOlderChats: () => [],
                removeOlderChat: (state, { chatId }) => state.filter((chat) => chat.id !== chatId),
            },
        ],
        nextChatsOffset: [null as number | null, { setNextChatsOffset: (_, { offset }) => offset }],
        loadingMoreChats: [false, { setLoadingMoreChats: (_, { loading }) => loading }],
        moreChatsError: [null as string | null, { setMoreChatsError: (_, { error }) => error }],
        question: [
            '',
            {
                setQuestion: (_, { question }) => question,
                openChat: () => '',
            },
        ],
        pendingQuestion: [
            null as string | null,
            {
                setPendingQuestion: (_, { pendingQuestion }) => pendingQuestion,
                openChat: () => null,
                chatLoaded: () => null,
            },
        ],
        chatSearch: [
            '',
            {
                setChatSearch: (_, { chatSearch }) => chatSearch,
            },
        ],
        asking: [
            false,
            {
                setAsking: (_, { asking }) => asking,
            },
        ],
        askError: [
            null as string | null,
            {
                setAskError: (_, { askError }) => askError,
                openChat: () => null,
            },
        ],
        chatId: [
            null as string | null,
            {
                openChat: (_, { chatId }) => chatId,
                setChatId: (_, { chatId }) => chatId,
            },
        ],
        chat: [
            null as PlaygroundChatApi | null,
            {
                openChat: () => null,
                chatLoaded: (_, { chat }) => chat,
            },
        ],
        chatError: [
            null as string | null,
            {
                setChatError: (_, { chatError }) => chatError,
                openChat: () => null,
                chatLoaded: () => null,
                pollFailed: (_, { error }) => error,
            },
        ],
        chatLoading: [
            false,
            {
                setChatLoading: (_, { chatLoading }) => chatLoading,
                openChat: (_, { chatId }) => Boolean(chatId),
                chatLoaded: () => false,
            },
        ],
        deletingChatId: [
            null as string | null,
            {
                setDeletingChatId: (_, { deletingChatId }) => deletingChatId,
            },
        ],
    }),
    selectors({
        chatHasOpenTurn: [(s) => [s.chat], (chat: PlaygroundChatApi | null): boolean => hasOpenTurn(chat)],
        chatGroups: [
            (s) => [s.chats, s.olderChats, s.chatSearch],
            (
                chats: PlaygroundChatListApi[],
                olderChats: PlaygroundChatListApi[],
                chatSearch: string
            ): PlaygroundChatGroup[] => {
                const ids = new Set(chats.map((chat) => chat.id))
                return groupPlaygroundChats([...chats, ...olderChats.filter((chat) => !ids.has(chat.id))], chatSearch)
            },
        ],
        askBlockedReason: [
            (s) => [s.chats, s.chatId, s.chatHasOpenTurn],
            (chats: PlaygroundChatListApi[], chatId: string | null, chatHasOpenTurn: boolean): string | null => {
                if (chatHasOpenTurn) {
                    return 'Wait for this answer to finish.'
                }
                const openElsewhere = chats.filter((listed) => listed.id !== chatId && listed.has_open_turn).length
                return openElsewhere >= MAX_OPEN_ANSWERS
                    ? `You have ${MAX_OPEN_ANSWERS} answers running. Wait for one to finish before you ask another question.`
                    : null
            },
        ],
        askDisabled: [
            (s) => [s.asking, s.askBlockedReason, s.question],
            (asking: boolean, askBlockedReason: string | null, question: string): boolean =>
                asking || askBlockedReason !== null || question.trim().length === 0,
        ],
    }),
    listeners(({ actions, values, cache }) => {
        // Every chat read takes a new id, so a slow older response cannot overwrite a newer one.
        const nextChatRequest = (): number => {
            cache.chatRequest = (cache.chatRequest ?? 0) + 1
            return cache.chatRequest
        }
        const isStale = (chatId: string, request: number): boolean =>
            cache.disposables.isDisposed || values.chatId !== chatId || cache.chatRequest !== request
        const schedulePoll = (): void => {
            cache.disposables.add(() => {
                const id = window.setTimeout(() => actions.poll(), POLL_MS)
                return () => window.clearTimeout(id)
            }, 'playgroundPoll')
        }

        return {
            loadMoreChats: async () => {
                if (values.loadingMoreChats || values.chatsLoading || values.nextChatsOffset === null) {
                    return
                }
                const offset = values.nextChatsOffset
                actions.setLoadingMoreChats(true)
                actions.setMoreChatsError(null)
                try {
                    const page = await listPlaygroundChats(offset)
                    if (cache.disposables.isDisposed) {
                        return
                    }
                    actions.appendOlderChats(page.results)
                    actions.setNextChatsOffset(page.next ? offset + page.results.length : null)
                } catch (error) {
                    if (!cache.disposables.isDisposed) {
                        actions.setMoreChatsError(errorDetail(error, "Couldn't load older chats. Try again."))
                    }
                } finally {
                    if (!cache.disposables.isDisposed) {
                        actions.setLoadingMoreChats(false)
                    }
                }
            },
            loadChatsSuccess: ({ chats }) => {
                // Other chats keep running in the background, so refresh the list until their spinners can clear.
                if (chats.some((chat) => chat.has_open_turn)) {
                    cache.disposables.add(() => {
                        const id = window.setTimeout(() => actions.loadChats(), LIST_POLL_MS)
                        return () => window.clearTimeout(id)
                    }, 'playgroundListPoll')
                }
            },
            openChat: async ({ chatId }) => {
                cache.disposables.dispose('playgroundPoll')
                const request = nextChatRequest()
                actions.setAsking(false)
                if (!chatId) {
                    return
                }
                try {
                    const chat = await getPlaygroundChat(chatId)
                    if (isStale(chatId, request)) {
                        return
                    }
                    actions.chatLoaded(chat)
                    if (hasOpenTurn(chat)) {
                        actions.setAsking(true)
                        schedulePoll()
                    }
                } catch (error) {
                    if (isStale(chatId, request)) {
                        return
                    }
                    actions.setChatLoading(false)
                    actions.setChatError(errorDetail(error, "Couldn't load this chat. Try again."))
                }
            },
            newChat: () => {
                if (router.values.location.pathname === urls.currentProject(urls.businessKnowledgePlayground())) {
                    actions.openChat(null)
                    return
                }
                router.actions.push(urls.businessKnowledgePlayground())
            },
            deleteChat: async ({ chatId }) => {
                if (values.deletingChatId) {
                    return
                }
                actions.setDeletingChatId(chatId)
                try {
                    await deletePlaygroundChat(chatId)
                    if (cache.disposables.isDisposed) {
                        return
                    }
                    actions.removeOlderChat(chatId)
                    actions.loadChats()
                    if (values.chatId === chatId) {
                        actions.newChat()
                    }
                } catch (error) {
                    if (cache.disposables.isDisposed) {
                        return
                    }
                    actions.setChatError(errorDetail(error, "Couldn't delete this chat. Try again."))
                } finally {
                    if (!cache.disposables.isDisposed) {
                        actions.setDeletingChatId(null)
                    }
                }
            },
            ask: async () => {
                if (values.asking || values.askBlockedReason) {
                    return
                }
                const question = values.question.trim()
                if (!question) {
                    return
                }
                actions.setAsking(true)
                actions.setAskError(null)
                actions.setPendingQuestion(question)
                actions.setQuestion('')
                const initialChatId = values.chatId
                let chatId = initialChatId
                try {
                    if (!chatId) {
                        const created = await createPlaygroundChat()
                        if (cache.disposables.isDisposed || values.chatId !== initialChatId) {
                            return
                        }
                        chatId = created.id
                        actions.setChatId(chatId)
                        router.actions.replace(urls.businessKnowledgePlayground(chatId))
                        actions.loadChats()
                    }
                    const chat = await askPlaygroundChat(chatId, question)
                    if (cache.disposables.isDisposed || values.chatId !== chatId) {
                        return
                    }
                    nextChatRequest()
                    actions.chatLoaded(chat)
                    actions.loadChats()
                    if (hasOpenTurn(chat)) {
                        actions.startPolling()
                    }
                } catch (error) {
                    if (cache.disposables.isDisposed || values.chatId !== chatId) {
                        return
                    }
                    actions.setPendingQuestion(null)
                    if (!values.question) {
                        actions.setQuestion(question)
                    }
                    actions.setAskError(errorDetail(error, "Couldn't start the answer. Try again."))
                    actions.setAsking(false)
                }
            },
            startPolling: () => {
                schedulePoll()
            },
            poll: async () => {
                const chatId = values.chatId
                if (!chatId) {
                    return
                }
                // The next poll starts only after this one returns, so responses arrive in order.
                const request = nextChatRequest()
                try {
                    const chat = await getPlaygroundChat(chatId)
                    if (isStale(chatId, request)) {
                        return
                    }
                    actions.chatLoaded(chat)
                    if (hasOpenTurn(chat)) {
                        schedulePoll()
                    }
                } catch (error) {
                    if (isStale(chatId, request)) {
                        return
                    }
                    if (error instanceof ApiError && error.status === 404) {
                        actions.pollFailed(errorDetail(error, "Couldn't check the answer. Try again."))
                        return
                    }
                    actions.setChatError(errorDetail(error, "Couldn't check the answer. Try again."))
                    schedulePoll()
                }
            },
            chatLoaded: ({ chat }) => {
                if (!hasOpenTurn(chat)) {
                    cache.disposables.dispose('playgroundPoll')
                    actions.setAsking(false)
                }
            },
            pollFailed: () => {
                cache.disposables.dispose('playgroundPoll')
                actions.setAsking(false)
            },
        }
    }),
    urlToAction(({ actions, values }) => ({
        [urls.businessKnowledgePlayground()]: () => {
            if (values.chatId !== null) {
                actions.openChat(null)
            }
        },
        [`${urls.businessKnowledgePlayground()}/:chatId`]: ({ chatId }) => {
            if (chatId && chatId !== values.chatId) {
                actions.openChat(chatId)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadChats()
    }),
])
