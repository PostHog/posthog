export const LIBRARY_SCOPE_ALL = 'all'
export const LIBRARY_SCOPE_UNFILED = 'unfiled'

function isLibraryScope(scope: string): boolean {
    return scope !== LIBRARY_SCOPE_ALL && scope !== LIBRARY_SCOPE_UNFILED
}

async function fileCreatedSource(sourceId: string, libraryIds: string[]): Promise<void> {
    if (libraryIds.length === 0) {
        return
    }
    // The source already exists here. Throwing would keep the create modal open and invite a duplicate submit.
    try {
        await updateSource(sourceId, { library_ids: libraryIds })
        posthog.capture('business knowledge source libraries changed', { library_count: libraryIds.length })
    } catch {
        lemonToast.warning('Source added, but it could not be added to its libraries. Add them from the source page.')
    }
}

function scopeIsKnown(scope: string, libraries: KnowledgeLibrary[]): boolean {
    return (
        scope === LIBRARY_SCOPE_ALL ||
        scope === LIBRARY_SCOPE_UNFILED ||
        libraries.some((library) => library.id === scope)
    )
}

