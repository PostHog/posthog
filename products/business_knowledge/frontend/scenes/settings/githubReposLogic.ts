import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { ApiConfig, ApiError } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'

import * as api from '../../generated/api'
import type { RepositoryConnectionApi } from '../../generated/api.schemas'

// Mirrors MAX_GITHUB_REPOS in products/business_knowledge/backend/github_repos.py.
export const MAX_GITHUB_REPOS = 20

function teamId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

function errorMessage(error: unknown, fallback: string): string {
    return (error instanceof ApiError && error.detail) || fallback
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface githubReposLogicValues {
    connecting: boolean
    connection: RepositoryConnectionApi | null
    connectionLoading: boolean
    disconnecting: boolean
    draftRepos: string[]
    saving: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface githubReposLogicActions {
    addRepo: (fullName: string) => {
        fullName: string
    }
    connectGithub: (integrationId: number) => {
        integrationId: number
    }
    connectGithubFailure: () => {
        value: true
    }
    connectGithubSuccess: (connection: RepositoryConnectionApi) => {
        connection: RepositoryConnectionApi
    }
    disconnectGithub: () => {
        value: true
    }
    disconnectGithubFailure: () => {
        value: true
    }
    disconnectGithubSuccess: (connection: RepositoryConnectionApi) => {
        connection: RepositoryConnectionApi
    }
    loadConnection: () => any
    loadConnectionFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadConnectionSuccess: (
        connection: RepositoryConnectionApi,
        payload?: any
    ) => {
        connection: RepositoryConnectionApi
        payload?: any
    }
    removeRepo: (fullName: string) => {
        fullName: string
    }
    saveRepos: () => {
        value: true
    }
    saveReposFailure: () => {
        value: true
    }
    saveReposSuccess: (connection: RepositoryConnectionApi) => {
        connection: RepositoryConnectionApi
    }
}

export type githubReposLogicType = MakeLogicType<githubReposLogicValues, githubReposLogicActions>

export const githubReposLogic = kea<githubReposLogicType>([
    path(['products', 'business_knowledge', 'frontend', 'settings', 'githubReposLogic']),
    actions({
        addRepo: (fullName: string) => ({ fullName }),
        removeRepo: (fullName: string) => ({ fullName }),
        saveRepos: true,
        saveReposSuccess: (connection: RepositoryConnectionApi) => ({ connection }),
        saveReposFailure: true,
        connectGithub: (integrationId: number) => ({ integrationId }),
        connectGithubSuccess: (connection: RepositoryConnectionApi) => ({ connection }),
        connectGithubFailure: true,
        disconnectGithub: true,
        disconnectGithubSuccess: (connection: RepositoryConnectionApi) => ({ connection }),
        disconnectGithubFailure: true,
    }),
    loaders(() => ({
        connection: [
            null as RepositoryConnectionApi | null,
            {
                loadConnection: async () => await api.businessKnowledgeRepositoriesStatusRetrieve(teamId()),
            },
        ],
    })),
    reducers({
        draftRepos: [
            [] as string[],
            {
                loadConnectionSuccess: (_, { connection }) => connection.repos,
                saveReposSuccess: (_, { connection }) => connection.repos,
                connectGithubSuccess: (_, { connection }) => connection.repos,
                disconnectGithubSuccess: () => [],
                addRepo: (repos, { fullName }) => {
                    const name = fullName.toLowerCase()
                    if (!name || repos.includes(name) || repos.length >= MAX_GITHUB_REPOS) {
                        return repos
                    }
                    return [...repos, name]
                },
                removeRepo: (repos, { fullName }) => repos.filter((repo) => repo !== fullName),
            },
        ],
        saving: [
            false,
            {
                saveRepos: () => true,
                saveReposSuccess: () => false,
                saveReposFailure: () => false,
            },
        ],
        connecting: [
            false,
            {
                connectGithub: () => true,
                connectGithubSuccess: () => false,
                connectGithubFailure: () => false,
            },
        ],
        disconnecting: [
            false,
            {
                disconnectGithub: () => true,
                disconnectGithubSuccess: () => false,
                disconnectGithubFailure: () => false,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        connectGithub: async ({ integrationId }) => {
            try {
                const connection = await api.businessKnowledgeRepositoriesConnectCreate(teamId(), {
                    integration_id: integrationId,
                })
                actions.connectGithubSuccess(connection)
                actions.loadConnectionSuccess(connection)
                posthog.capture('business knowledge repos connected')
            } catch (error) {
                actions.connectGithubFailure()
                lemonToast.error(errorMessage(error, 'Could not connect GitHub. Try again.'))
            }
        },
        disconnectGithub: async () => {
            try {
                const connection = await api.businessKnowledgeRepositoriesDisconnectCreate(teamId())
                actions.disconnectGithubSuccess(connection)
                actions.loadConnectionSuccess(connection)
                posthog.capture('business knowledge repos disconnected')
            } catch (error) {
                actions.disconnectGithubFailure()
                lemonToast.error(errorMessage(error, 'Could not disconnect GitHub. Try again.'))
            }
        },
        saveRepos: async () => {
            try {
                const connection = await api.businessKnowledgeRepositoriesSelectionCreate(teamId(), {
                    repos: values.draftRepos,
                })
                actions.saveReposSuccess(connection)
                actions.loadConnectionSuccess(connection)
                posthog.capture('business knowledge repos selected', { repo_count: connection.repos.length })
            } catch (error) {
                actions.saveReposFailure()
                lemonToast.error(errorMessage(error, 'Could not save repositories. Try again.'))
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadConnection()
    }),
])
