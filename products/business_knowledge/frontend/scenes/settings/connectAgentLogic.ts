import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { ApiConfig, ApiError } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'

import * as api from '../../generated/api'
import type { KnowledgeKeyApi, KnowledgeLibraryApi } from '../../generated/api.schemas'

// Mirrors the max_length of `label` in products/business_knowledge/backend/api/key_serializers.py.
export const MAX_KEY_LABEL_LENGTH = 40

export const ALL_KNOWLEDGE = 'all'

function teamId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface connectAgentLogicValues {
    createDisabledReason: string | undefined
    createdKey: KnowledgeKeyApi | null
    createdKeys: KnowledgeKeyApi[]
    creating: boolean
    keys: KnowledgeKeyApi[] | null
    keysLoading: boolean
    label: string
    libraries: KnowledgeLibraryApi[] | null
    librariesLoading: boolean
    libraryNames: Record<string, string>
    listedKeys: KnowledgeKeyApi[] | null
    reads: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface connectAgentLogicActions {
    createKey: () => {
        value: true
    }
    createKeyFailure: () => {
        value: true
    }
    createKeySuccess: (key: KnowledgeKeyApi) => {
        key: KnowledgeKeyApi
    }
    loadKeys: () => any
    loadKeysFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadKeysSuccess: (
        keys: KnowledgeKeyApi[],
        payload?: any
    ) => {
        keys: KnowledgeKeyApi[]
        payload?: any
    }
    loadLibraries: () => any
    loadLibrariesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadLibrariesSuccess: (
        libraries: KnowledgeLibraryApi[],
        payload?: any
    ) => {
        libraries: KnowledgeLibraryApi[]
        payload?: any
    }
    setLabel: (label: string) => {
        label: string
    }
    setReads: (reads: string | null) => {
        reads: string | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface connectAgentLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        listedKeys: (keys: KnowledgeKeyApi[] | null, createdKeys: KnowledgeKeyApi[]) => KnowledgeKeyApi[] | null
        libraryNames: (libraries: KnowledgeLibraryApi[] | null) => Record<string, string>
        createDisabledReason: (reads: string | null, label: string, creating: boolean) => string | undefined
    }
}

export type connectAgentLogicType = MakeLogicType<
    connectAgentLogicValues,
    connectAgentLogicActions,
    Record<string, any>,
    connectAgentLogicMeta
>

export const connectAgentLogic = kea<connectAgentLogicType>([
    path(['products', 'business_knowledge', 'frontend', 'settings', 'connectAgentLogic']),
    actions({
        setReads: (reads: string | null) => ({ reads }),
        setLabel: (label: string) => ({ label }),
        createKey: true,
        createKeySuccess: (key: KnowledgeKeyApi) => ({ key }),
        createKeyFailure: true,
    }),
    loaders(() => ({
        libraries: [
            null as KnowledgeLibraryApi[] | null,
            {
                loadLibraries: async () => await api.businessKnowledgeLibrariesList(teamId()),
            },
        ],
        keys: [
            null as KnowledgeKeyApi[] | null,
            {
                loadKeys: async () => await api.businessKnowledgeKeysList(teamId()),
            },
        ],
    })),
    reducers({
        // ALL_KNOWLEDGE or a library ID. Null until the admin chooses, so no key gets the widest access by default.
        reads: [
            null as string | null,
            {
                setReads: (_, { reads }) => reads,
                createKeySuccess: () => null,
            },
        ],
        label: [
            '',
            {
                setLabel: (_, { label }) => label,
                createKeySuccess: () => '',
            },
        ],
        creating: [
            false,
            {
                createKey: () => true,
                createKeySuccess: () => false,
                createKeyFailure: () => false,
            },
        ],
        // The API returns the key value once, so it lives here until the panel unmounts.
        createdKey: [
            null as KnowledgeKeyApi | null,
            {
                createKeySuccess: (_, { key }) => key,
            },
        ],
        createdKeys: [
            [] as KnowledgeKeyApi[],
            {
                createKeySuccess: (created, { key }) => [{ ...key, value: null }, ...created],
            },
        ],
    }),
    selectors({
        // A list request that started before a create answers without the new key, so the keys made here are merged in.
        listedKeys: [
            (s) => [s.keys, s.createdKeys],
            (keys: KnowledgeKeyApi[] | null, createdKeys: KnowledgeKeyApi[]): KnowledgeKeyApi[] | null => {
                if (!keys) {
                    return null
                }
                const loadedIds = new Set(keys.map((key) => key.id))
                return [...createdKeys.filter((key) => !loadedIds.has(key.id)), ...keys]
            },
        ],
        libraryNames: [
            (s) => [s.libraries],
            (libraries: KnowledgeLibraryApi[] | null): Record<string, string> =>
                Object.fromEntries((libraries ?? []).map((library) => [library.id, library.name])),
        ],
        createDisabledReason: [
            (s) => [s.reads, s.label, s.creating],
            (reads: string | null, label: string, creating: boolean): string | undefined => {
                if (creating) {
                    return 'Creating the key'
                }
                if (!reads) {
                    return 'Choose what the agent can read'
                }
                if (!label.trim()) {
                    return 'Name the key'
                }
                return undefined
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        createKey: async () => {
            if (!values.reads) {
                actions.createKeyFailure()
                return
            }
            try {
                const key = await api.businessKnowledgeKeysCreate(teamId(), {
                    label: values.label.trim(),
                    library_id: values.reads === ALL_KNOWLEDGE ? null : values.reads,
                })
                actions.createKeySuccess(key)
                posthog.capture('business knowledge agent key created')
            } catch (error) {
                actions.createKeyFailure()
                lemonToast.error((error instanceof ApiError && error.detail) || 'Could not create the key. Try again.')
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadLibraries()
        actions.loadKeys()
    }),
])
