import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers } from 'kea'
import posthog from 'posthog-js'

import { getDocumentWindow, searchKnowledge } from '../../api'
import type { KnowledgeDocumentWindowApi, KnowledgeSearchResultApi } from '../../generated/api.schemas'
import { type PlaygroundCitationRequest, errorDetail } from './playgroundDisplay'

export type PlaygroundCitationChunk = KnowledgeSearchResultApi | KnowledgeDocumentWindowApi

export interface PlaygroundCitationsLogicProps {
    citationKey: string
    request: PlaygroundCitationRequest
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface playgroundCitationsLogicValues {
    chunks: PlaygroundCitationChunk[] | null
    chunksError: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface playgroundCitationsLogicActions {
    loadChunks: () => {
        value: true
    }
    setChunks: (chunks: PlaygroundCitationChunk[]) => {
        chunks: PlaygroundCitationChunk[]
    }
    setChunksError: (chunksError: string) => {
        chunksError: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface playgroundCitationsLogicMeta {
    key: string
}

export type playgroundCitationsLogicType = MakeLogicType<
    playgroundCitationsLogicValues,
    playgroundCitationsLogicActions,
    PlaygroundCitationsLogicProps,
    playgroundCitationsLogicMeta
>

export const playgroundCitationsLogic = kea<playgroundCitationsLogicType>([
    props({} as PlaygroundCitationsLogicProps),
    key((props) => props.citationKey),
    path((key) => ['products', 'business_knowledge', 'frontend', 'scenes', 'playgroundCitationsLogic', key]),
    actions({
        loadChunks: true,
        setChunks: (chunks: PlaygroundCitationChunk[]) => ({ chunks }),
        setChunksError: (chunksError: string) => ({ chunksError }),
    }),
    reducers({
        chunks: [
            null as PlaygroundCitationChunk[] | null,
            {
                setChunks: (_, { chunks }) => chunks,
            },
        ],
        chunksError: [
            null as string | null,
            {
                loadChunks: () => null,
                setChunksError: (_, { chunksError }) => chunksError,
            },
        ],
    }),
    listeners(({ actions, props, cache }) => ({
        loadChunks: async () => {
            const { request } = props
            try {
                const chunks =
                    request.kind === 'search'
                        ? await searchKnowledge(request.params)
                        : await getDocumentWindow(request.documentId, request.params)
                if (!cache.disposables.isDisposed) {
                    actions.setChunks(chunks)
                }
            } catch (error) {
                if (!cache.disposables.isDisposed) {
                    actions.setChunksError(errorDetail(error, "Couldn't load these chunks. Try again."))
                }
            }
        },
    })),
    // Replays the logged call on expand. The run does not store tool output, so changed sources give different chunks.
    afterMount(({ actions, props }) => {
        posthog.capture('business knowledge playground citations opened', { kind: props.request.kind })
        actions.loadChunks()
    }),
])
