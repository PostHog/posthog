export const knowledgeLibraryLogic = kea<knowledgeLibraryLogicType>([
    props({} as KnowledgeLibraryLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'business_knowledge', 'frontend', 'library', 'knowledgeLibraryLogic', key]),
    actions({
        markLibraryNotFound: true,
        openDialog: (dialog: LibraryEditDialog) => ({ dialog }),
        closeDialog: true,
        renameLibrary: (name: string) => ({ name }),
        saveRepos: (repos: string[]) => ({ repos }),
        deleteLibrary: true,
        finishSave: true,
        addSource: (sourceId: string) => ({ sourceId }),
        removeSource: (sourceId: string) => ({ sourceId }),
        finishSourceChange: (sourceId: string) => ({ sourceId }),
    }),
    loaders(({ props, actions, values }) => ({
        library: [
            null as KnowledgeLibraryApi | null,
            {
                loadLibrary: async () => {
                    try {
                        return await getLibrary(props.id)
                    } catch (error: unknown) {
                        // Catch 404 here so initKea does not toast. The scene renders NotFound.
                        if ((error as { status?: number } | null)?.status === 404) {
                            actions.markLibraryNotFound()
                            return null
                        }
                        throw error
                    }
                },
            },
        ],
        sources: [
            null as KnowledgeSourceApi[] | null,
            {
                loadSources: async () => await listSources({ libraryId: props.id }),
            },
        ],
        projectSources: [
            null as KnowledgeSourceApi[] | null,
            {
                // The picker searches on the server, because one page does not hold every source of a large project.
                loadProjectSources: async (search: string | undefined, breakpoint) => {
                    if (search !== undefined) {
                        await breakpoint(300)
                    }
                    const sources = await listSources({ search: search ?? values.sourceSearch })
                    breakpoint()
                    return sources
                },
            },
        ],
    })),
    reducers({
        libraryNotFound: [
            false,
            {
                markLibraryNotFound: () => true,
            },
        ],
        dialog: [
            null as LibraryEditDialog | null,
            {
                openDialog: (_, { dialog }) => dialog,
                closeDialog: () => null,
            },
        ],
        saving: [
            false,
            {
                renameLibrary: () => true,
                saveRepos: () => true,
                deleteLibrary: () => true,
                finishSave: () => false,
            },
        ],
        sourceSearch: [
            '',
            {
                loadProjectSources: (state, search) => search ?? state,
            },
        ],
        projectSourcesFailed: [
            false,
            {
                loadProjectSources: () => false,
                loadProjectSourcesFailure: () => true,
            },
        ],
        changingSourceIds: [
            [] as string[],
            {
                addSource: (state, { sourceId }) => [...state, sourceId],
                removeSource: (state, { sourceId }) => [...state, sourceId],
                finishSourceChange: (state, { sourceId }) => state.filter((id) => id !== sourceId),
            },
        ],
    }),
    selectors({
        breadcrumbs: [
            (s) => [s.library],
            (library: KnowledgeLibraryApi | null): Breadcrumb[] => [
                {
                    key: Scene.BusinessKnowledgeLibraries,
                    name: 'Libraries',
                    path: urls.businessKnowledgeLibraries(),
                    iconType: 'business_knowledge',
                },
                {
                    key: Scene.BusinessKnowledgeLibrary,
                    name: library?.name ?? 'Library',
                    iconType: 'business_knowledge',
                },
            ],
        ],
        addableSources: [
            (s) => [s.projectSources, s.sources],
            (
                projectSources: KnowledgeSourceApi[] | null,
                sources: KnowledgeSourceApi[] | null
            ): KnowledgeSourceApi[] => {
                const inLibrary = new Set((sources ?? []).map((source) => source.id))
                return (projectSources ?? []).filter((source) => !inLibrary.has(source.id))
            },
        ],
    }),
    listeners(({ actions, cache, props, values }) => {
        async function changeSourceLibraries(
            sourceId: string,
            change: (libraryIds: string[]) => string[]
        ): Promise<void> {
            try {
                // The request replaces the whole list, so read the list now and keep a change another person just made.
                const source = await getSource(sourceId)
                const libraryIds = change([...source.library_ids])
                await updateSource(sourceId, { library_ids: libraryIds })
                // pinned: analytics event name. Renaming it breaks insights built on it.
                posthog.capture('business knowledge source libraries changed', {
                    library_count: libraryIds.length,
                    surface: 'library',
                })
                actions.loadLibrary()
                actions.loadSources()
                actions.loadProjectSources(undefined)
            } catch (error: any) {
                lemonToast.error(error?.detail || error?.data?.library_ids?.[0] || 'Could not update the library.')
            } finally {
                actions.finishSourceChange(sourceId)
            }
        }

        function pollPendingSources(sources: KnowledgeSourceApi[] | null, afterFailure: boolean): void {
            // Ingestion and embedding run in the background. Poll until each source settles.
            const isProcessing = (sources ?? []).some((source) => source.status === 'processing')
            const isEmbedding = (sources ?? []).some(
                (source) => source.status === 'ready' && source.embedding_status === 'pending'
            )
            if (!isProcessing && !isEmbedding) {
                cache.disposables.dispose('pollProcessing')
                return
            }
            const delayMs = afterFailure || !isProcessing ? 60000 : 3000
            cache.disposables.add(() => {
                const id = setTimeout(() => actions.loadSources(), delayMs)
                return () => clearTimeout(id)
            }, 'pollProcessing')
        }

        return {
            renameLibrary: async ({ name }) => {
                try {
                    actions.loadLibrarySuccess(await updateLibrary(props.id, { name }))
                    // pinned: analytics event name. Renaming it breaks insights built on it.
                    posthog.capture('business knowledge library renamed')
                    actions.closeDialog()
                } catch (error: any) {
                    lemonToast.error(error?.detail || error?.data?.name?.[0] || 'Could not rename the library.')
                } finally {
                    actions.finishSave()
                }
            },
            saveRepos: async ({ repos }) => {
                try {
                    actions.loadLibrarySuccess(await updateLibrary(props.id, { repos }))
                    // pinned: analytics event name. Renaming it breaks insights built on it.
                    posthog.capture('business knowledge library repos changed')
                    actions.closeDialog()
                } catch (error: any) {
                    lemonToast.error(error?.detail || error?.data?.repos?.[0] || 'Could not save repositories.')
                } finally {
                    actions.finishSave()
                }
            },
            deleteLibrary: async () => {
                try {
                    await deleteLibrary(props.id)
                    // pinned: analytics event name. Renaming it breaks insights built on it.
                    posthog.capture('business knowledge library deleted')
                    router.actions.push(urls.businessKnowledgeLibraries())
                } catch (error: any) {
                    lemonToast.error(error?.detail || 'Could not delete the library.')
                } finally {
                    actions.finishSave()
                }
            },
            addSource: async ({ sourceId }) => {
                await changeSourceLibraries(sourceId, (libraryIds) => [...new Set([...libraryIds, props.id])])
            },
            removeSource: async ({ sourceId }) => {
                await changeSourceLibraries(sourceId, (libraryIds) => libraryIds.filter((id) => id !== props.id))
            },
            loadSourcesSuccess: ({ sources }) => {
                pollPendingSources(sources, false)
            },
            loadSourcesFailure: () => {
                // A failed poll must not end the polling. The last known list says if a source is still pending.
                pollPendingSources(values.sources, true)
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadLibrary()
        actions.loadSources()
        actions.loadProjectSources(undefined)
    }),
])
