/**
 * A canvas's version history and drafts, and browsing through them: undo and redo step
 * through published versions, a draft can be previewed, and either can be made live.
 */
export const canvasHistoryLogic = kea<canvasHistoryLogicType>([
    props({} as CanvasHistoryLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'canvas', 'frontend', 'history', 'canvasHistoryLogic', key]),
    connect((props: CanvasHistoryLogicProps) => ({
        values: [
            canvasSceneLogic({ id: props.id }),
            ['currentProjectId', 'view', 'isGenerating', 'liveBuild', 'canvas'],
        ],
        actions: [
            canvasSceneLogic({ id: props.id }),
            ['loadView', 'loadBuilds', 'loadViewSuccess', 'loadBuildsSuccess', 'startPolling'],
        ],
    })),
    actions({
        setBrowseVersion: (versionId: string | null) => ({ versionId }),
        undo: true,
        redo: true,
        requestConfirmation: (confirmation: CanvasHistoryConfirmation) => ({ confirmation }),
        cancelConfirmation: true,
        confirm: true,
        confirmFinished: true,
    }),
    loaders(({ props, values }) => ({
        versions: [
            [] as CanvasVersionApi[],
            {
                loadVersions: async () =>
                    values.currentProjectId
                        ? (
                              await canvasesVersionsRetrieve(String(values.currentProjectId), props.id, {
                                  limit: HISTORY_PAGE_SIZE,
                              })
                          ).results
                        : [],
            },
        ],
        drafts: [
            [] as CanvasDraftApi[],
            {
                loadDrafts: async () =>
                    values.currentProjectId
                        ? await canvasesDraftsRetrieve(String(values.currentProjectId), props.id)
                        : [],
            },
        ],
        // The full recent-build window, for the timeline. The scene polls only the slim view.
        buildHistory: [
            null as CanvasBuildsResponseApi | null,
            {
                loadBuildHistory: async () =>
                    values.currentProjectId
                        ? await canvasesBuildsRetrieve(String(values.currentProjectId), props.id)
                        : null,
            },
        ],
        browsedRender: [
            null as CanvasBrowsedRender | null,
            {
                loadBrowsedRender: async (
                    { versionId }: { versionId: string },
                    breakpoint
                ): Promise<CanvasBrowsedRender> => {
                    const projectId = String(values.currentProjectId)
                    const builds = await canvasesBuildsRetrieve(projectId, props.id, {
                        scope: 'slim',
                        version_id: versionId,
                    }).catch(() => null)
                    breakpoint()
                    const build =
                        builds?.builds.find(
                            (candidate) =>
                                candidate.source_version_id === versionId &&
                                candidate.build_status === 'ready' &&
                                !!candidate.artifact_url
                        ) ?? null
                    if (build) {
                        return { versionId, build, project: null }
                    }
                    const source = await canvasesSourceRetrieve(projectId, props.id, { version_id: versionId })
                    breakpoint()
                    return { versionId, build: null, project: source.project }
                },
            },
        ],
    })),
    reducers({
        browseVersionId: [
            null as string | null,
            {
                setBrowseVersion: (_, { versionId }) => versionId,
            },
        ],
        browsedRender: {
            setBrowseVersion: () => null,
        },
        confirmation: [
            null as CanvasHistoryConfirmation | null,
            {
                requestConfirmation: (_, { confirmation }) => confirmation,
                cancelConfirmation: () => null,
                confirmFinished: () => null,
            },
        ],
        confirming: [
            false,
            {
                confirm: () => true,
                confirmFinished: () => false,
            },
        ],
    }),
    selectors({
        headVersionId: [
            (s) => [s.view],
            (view: CanvasViewResponseApi | null): string | null => view?.current_version_id ?? null,
        ],
        navigation: [
            (s) => [s.versions, s.headVersionId, s.browseVersionId],
            (
                versions: CanvasVersionApi[],
                headVersionId: string | null,
                browseVersionId: string | null
            ): CanvasVersionNavigation => canvasVersionNavigation({ versions, headVersionId, browseVersionId }),
        ],
        // Stepping through versions while an agent writes a new one would show a version it is about to replace.
        canUndo: [
            (s) => [s.navigation, s.isGenerating],
            (navigation: CanvasVersionNavigation, isGenerating: boolean): boolean =>
                !isGenerating && navigation.canUndo,
        ],
        canRedo: [
            (s) => [s.navigation, s.isGenerating],
            (navigation: CanvasVersionNavigation, isGenerating: boolean): boolean =>
                !isGenerating && navigation.canRedo,
        ],
        browsedDraft: [
            (s) => [s.drafts, s.browseVersionId],
            (drafts: CanvasDraftApi[], browseVersionId: string | null): CanvasDraftApi | null =>
                (browseVersionId && drafts.find((draft) => draft.version_id === browseVersionId)) || null,
        ],
        browsedVersion: [
            (s) => [s.versions, s.browseVersionId],
            (versions: CanvasVersionApi[], browseVersionId: string | null): CanvasVersionApi | null =>
                (browseVersionId && versions.find((version) => version.id === browseVersionId)) || null,
        ],
        /** The source version on screen: the browsed one, else the live build's, else the head. */
        displayedVersionId: [
            (s) => [s.browseVersionId, s.liveBuild, s.headVersionId],
            (browseVersionId: string | null, liveBuild: CanvasBuildApi | null, headVersionId: string | null) =>
                browseVersionId ?? liveBuild?.source_version_id ?? headVersionId,
        ],
        /** "V3" for the third published version, the label comments and the timeline share. */
        versionLabels: [
            (s) => [s.versions],
            (versions: CanvasVersionApi[]): Record<string, string> =>
                Object.fromEntries(versions.map((version, index) => [version.id, `V${versions.length - index}`])),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        setBrowseVersion: ({ versionId }) => {
            if (versionId && values.currentProjectId) {
                actions.loadBrowsedRender({ versionId })
            }
        },
        undo: () => {
            if (values.canUndo && values.navigation.undoTargetId) {
                actions.setBrowseVersion(values.navigation.undoTargetId)
            }
        },
        redo: () => {
            // A null target steps onto the head, which ends the browse.
            if (values.canRedo) {
                actions.setBrowseVersion(values.navigation.redoTargetId)
            }
        },
        loadBuildsSuccess: ({ builds }) => {
            const history = values.buildHistory
            if (!builds || !history || values.buildHistoryLoading) {
                return
            }
            if (
                builds.current_version_id !== history.current_version_id ||
                builds.published_build_id !== history.published_build_id ||
                builds.builds.some(
                    (build) =>
                        history.builds.find((entry) => entry.id === build.id)?.build_status !== build.build_status
                )
            ) {
                actions.loadBuildHistory()
            }
        },
        loadViewSuccess: ({ view }) => {
            if (values.buildHistory && !values.buildHistoryLoading) {
                actions.loadBuildHistory()
            }
            // A new head version, or a draft an agent staged, shows up in the history.
            if (view) {
                actions.loadVersions()
                actions.loadDrafts()
            }
        },
        loadVersionsSuccess: () => {
            if (
                shouldClearCanvasBrowse({
                    browseTargetIds: [
                        ...values.versions.map((version) => version.id),
                        ...values.drafts.map((draft) => draft.version_id),
                    ],
                    loading: values.draftsLoading,
                    browseVersionId: values.browseVersionId,
                })
            ) {
                actions.setBrowseVersion(null)
            }
        },
        loadBrowsedRenderFailure: ({ error }) => {
            toast.error({ title: "Couldn't load that version", description: error || 'Try again in a moment.' })
        },
        confirm: async () => {
            const confirmation = values.confirmation
            const canvas = values.canvas
            if (!confirmation || !canvas || !values.currentProjectId) {
                actions.confirmFinished()
                return
            }
            const projectId = String(values.currentProjectId)
            const body = { version_id: confirmation.versionId, expected_current_version_id: values.headVersionId }
            const actionType = confirmation.kind === 'revert' ? 'revert' : 'promote_draft'
            try {
                if (confirmation.kind === 'revert') {
                    await canvasesRevertCreate(projectId, props.id, body)
                } else {
                    await canvasesPromoteCreate(projectId, props.id, body)
                }
                captureCanvasAction(actionType, { dashboard_id: canvas.id, channel_id: canvas.channel, success: true })
                toast.success(
                    confirmation.kind === 'revert'
                        ? { title: 'Reverted', description: 'The canvas rebuilds from that version.' }
                        : { title: 'Published the draft', description: 'It is live once its build is ready.' }
                )
                actions.setBrowseVersion(null)
                actions.loadView()
                actions.loadBuilds()
                actions.startPolling()
                if (values.buildHistory) {
                    actions.loadBuildHistory()
                }
            } catch (error) {
                captureCanvasAction(actionType, { dashboard_id: canvas.id, channel_id: canvas.channel, success: false })
                const status = (error as { status?: number } | null)?.status
                toast.error(
                    status === 409
                        ? {
                              title: 'Someone changed this canvas since you opened it',
                              description: 'Check the latest version and try again.',
                          }
                        : {
                              title: `Couldn't ${confirmation.kind === 'revert' ? 'revert the canvas' : 'publish the draft'}`,
                              description: error instanceof Error ? error.message : 'Try again in a moment.',
                          }
                )
            } finally {
                actions.confirmFinished()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.view) {
            actions.loadVersions()
            actions.loadDrafts()
        }
    }),
])
