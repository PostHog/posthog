/** A prompt whose canvas exists but whose build did not start. The canvas page picks it up. */
export interface CanvasStartHandoff {
    canvasId: string
    instruction: string
    fromSuggestion: boolean
}

function pickCanvasSpaceId(
    spaces: CanvasSpace[] | null,
    chosen: string | null,
    requested: string | null
): string | null {
    if (!spaces) {
        return null
    }
    const has = (id: string | null): id is string => !!id && spaces.some((space) => space.id === id)
    if (has(chosen)) {
        return chosen
    }
    if (has(requested)) {
        return requested
    }
    return (spaces.find((space) => space.system_role === 'personal') ?? spaces[0])?.id ?? null
}

