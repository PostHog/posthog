/**
 * The new canvas start page: a prompt and a space. Sending creates the canvas, starts the
 * agent that builds it, and replaces the page with the canvas, so Back skips the empty start page.
 */
export const canvasNewLogic = kea<canvasNewLogicType>([
    path(['products', 'canvas', 'frontend', 'newCanvas', 'canvasNewLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        setInstruction: (instruction: string, fromSuggestion: boolean) => ({ instruction, fromSuggestion }),
        setRequestedSpaceId: (spaceId: string | null) => ({ spaceId }),
        setSelectedSpaceId: (spaceId: string) => ({ spaceId }),
        send: true,
        sendStarted: true,
        sendFinished: true,
        sent: true,
        handOffStart: (handoff: CanvasStartHandoff) => ({ handoff }),
        clearStartHandoff: true,
    }),
    loaders(({ values }) => ({
        spaces: [
            null as CanvasSpace[] | null,
            {
                loadSpaces: async () =>
                    values.currentProjectId ? await loadCanvasSpaces(String(values.currentProjectId)) : [],
            },
        ],
    })),
    reducers({
        instruction: [
            '',
            {
                setInstruction: (_, { instruction }) => instruction,
                sent: () => '',
                handOffStart: () => '',
            },
        ],
        fromSuggestion: [
            false,
            {
                setInstruction: (_, { fromSuggestion }) => fromSuggestion,
                sent: () => false,
                handOffStart: () => false,
            },
        ],
        requestedSpaceId: [
            null as string | null,
            {
                setRequestedSpaceId: (_, { spaceId }) => spaceId,
            },
        ],
        chosenSpaceId: [
            null as string | null,
            {
                setRequestedSpaceId: () => null,
                setSelectedSpaceId: (_, { spaceId }) => spaceId,
            },
        ],
        sending: [
            false,
            {
                sendStarted: () => true,
                sendFinished: () => false,
            },
        ],
        spacesUnavailable: [
            false,
            {
                loadSpaces: () => false,
                loadSpacesFailure: () => true,
            },
        ],
        startHandoff: [
            null as CanvasStartHandoff | null,
            {
                handOffStart: (_, { handoff }) => handoff,
                clearStartHandoff: () => null,
            },
        ],
    }),
    selectors({
        selectedSpaceId: [
            (s) => [s.spaces, s.chosenSpaceId, s.requestedSpaceId],
            (spaces: CanvasSpace[] | null, chosen: string | null, requested: string | null): string | null =>
                pickCanvasSpaceId(spaces, chosen, requested),
        ],
        selectedSpace: [
            (s) => [s.spaces, s.selectedSpaceId],
            (spaces: CanvasSpace[] | null, selectedSpaceId: string | null): CanvasSpace | null =>
                spaces?.find((space) => space.id === selectedSpaceId) ?? null,
        ],
        sendDisabledReason: [
            (s) => [s.instruction, s.spaces, s.spacesUnavailable, s.selectedSpaceId],
            (
                instruction: string,
                spaces: CanvasSpace[] | null,
                spacesUnavailable: boolean,
                selectedSpaceId: string | null
            ): string | null => {
                if (spacesUnavailable) {
                    return 'Your spaces didn’t load. Try again to pick one.'
                }
                if (!spaces) {
                    return 'Loading your spaces'
                }
                if (!selectedSpaceId) {
                    return 'You don’t have a space to put a canvas in yet'
                }
                if (!instruction.trim()) {
                    return 'Describe the canvas first'
                }
                return null
            },
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                { key: 'views', name: 'Views', path: urls.views() },
                { key: 'CanvasNew', name: 'New canvas' },
            ],
        ],
    }),
    listeners(({ actions, values }) => ({
        send: async () => {
            const projectId = values.currentProjectId ? String(values.currentProjectId) : null
            const space = values.selectedSpace
            const instruction = values.instruction.trim()
            const fromSuggestion = values.fromSuggestion
            if (values.sending || values.sendDisabledReason || !projectId || !space) {
                return
            }
            actions.sendStarted()
            const stillOnStartPage = (): boolean =>
                removeProjectIdIfPresent(router.values.location.pathname) === urls.canvasNew()
            try {
                let canvas: CanvasApi
                try {
                    canvas = await canvasesCreate(projectId, {
                        channel_id: space.id,
                        name: UNTITLED_CANVAS_NAME,
                        template_id: FREEFORM_TEMPLATE_ID,
                    })
                } catch (error) {
                    toast.error({
                        title: "Couldn't create the canvas",
                        description: error instanceof Error ? error.message : 'Try again in a moment.',
                    })
                    return
                }
                posthog.capture(CANVAS_EVENTS.dashboardAction, {
                    action_type: 'create',
                    surface: 'web_new_canvas_page',
                    channel_id: space.id,
                    dashboard_id: canvas.id,
                    template_id: FREEFORM_TEMPLATE_ID,
                })
                try {
                    await startCanvasGeneration({
                        projectId,
                        canvas,
                        spaceName: space.name,
                        instruction,
                        fromSuggestion,
                        surface: 'web_new_canvas_page',
                    })
                    actions.sent()
                } catch (error) {
                    // The canvas exists, so the person lands on it with the prompt kept, ready to send again.
                    actions.handOffStart({ canvasId: canvas.id, instruction, fromSuggestion })
                    toast.error({
                        title: "Couldn't start building the canvas",
                        description: error instanceof Error ? error.message : 'Try again in a moment.',
                    })
                }
                if (stillOnStartPage()) {
                    router.actions.replace(urls.canvasDetail(canvas.id))
                }
            } finally {
                actions.sendFinished()
            }
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.canvasNew()]: (_, searchParams) => {
            if (values.sending) {
                return
            }
            actions.setRequestedSpaceId(typeof searchParams.space === 'string' ? searchParams.space : null)
            actions.loadSpaces()
        },
    })),
])
