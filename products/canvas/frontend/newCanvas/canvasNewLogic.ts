// pinned: `starter_id` of the create event for a canvas started without a prompt, shared with PostHog Desktop's starters
const BLANK_STARTER_ID = 'blank'

/** A prompt whose canvas exists but whose build did not start. The canvas page picks it up. */
export interface CanvasStartHandoff {
    canvasId: string
    instruction: string
    fromSuggestion: boolean
}

function pickCanvasSpaceId(
    spaces: CanvasSpace[] | null,
    chosen: string | null,
    requested: string | null
): string | null {
    if (!spaces) {
        return null
    }
    const privateId = visibilitySpace(spaces, 'private')?.id ?? null
    const publicId = visibilitySpace(spaces, 'public')?.id ?? null
    if (chosen && (chosen === privateId || chosen === publicId)) {
        return chosen
    }
    const requestedSpace = spaces.find((space) => space.id === requested)
    if (requestedSpace && publicId && canvasVisibility(requestedSpace) === 'public') {
        return publicId
    }
    return privateId ?? publicId
}

