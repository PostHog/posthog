import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { projectLogic } from 'scenes/projectLogic'
import { urls } from 'scenes/urls'

import { CANVAS_EVENTS } from '../canvasAnalytics'
import { CanvasSpace, loadCanvasSpaces } from '../canvasTasksApi'
import { CANVAS_TEMPLATES, CanvasTemplate, FREEFORM_TEMPLATE_ID, UNTITLED_CANVAS_NAME } from '../canvasTemplates'
import { canvasesCreate } from '../generated/api'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newCanvasDialogLogicValues {
    currentProjectId: number | null // projectLogic
    chosenSpaceId: string | null
    creating: boolean
    isOpen: boolean
    pendingComposerFocusId: string | null
    requestedSpaceId: string | null
    selectedSpaceId: string | null
    selectedTemplateId: string
    spaces: CanvasSpace[] | null
    spacesLoading: boolean
    spacesUnavailable: boolean
    templates: CanvasTemplate[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newCanvasDialogLogicActions {
    canvasCreated: (canvasId: string) => {
        canvasId: string
    }
    closeNewCanvasDialog: () => {
        value: true
    }
    composerFocused: () => {
        value: true
    }
    createCanvas: () => {
        value: true
    }
    createCanvasFinished: () => {
        value: true
    }
    loadSpaces: () => any
    loadSpacesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSpacesSuccess: (
        spaces: CanvasSpace[],
        payload?: any
    ) => {
        spaces: CanvasSpace[]
        payload?: any
    }
    openNewCanvasDialog: (spaceId?: string | null) => {
        spaceId: string | null
    }
    setSelectedSpaceId: (spaceId: string) => {
        spaceId: string
    }
    setSelectedTemplateId: (templateId: string) => {
        templateId: string
    }
}

export type newCanvasDialogLogicType = MakeLogicType<newCanvasDialogLogicValues, newCanvasDialogLogicActions>

export const newCanvasDialogLogic = kea<newCanvasDialogLogicType>([
    path(['products', 'canvas', 'frontend', 'newCanvas', 'newCanvasDialogLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        openNewCanvasDialog: (spaceId?: string | null) => ({ spaceId: spaceId ?? null }),
        closeNewCanvasDialog: true,
        setSelectedSpaceId: (spaceId: string) => ({ spaceId }),
        setSelectedTemplateId: (templateId: string) => ({ templateId }),
        createCanvas: true,
        createCanvasFinished: true,
        canvasCreated: (canvasId: string) => ({ canvasId }),
        composerFocused: true,
    }),
    loaders(({ values }) => ({
        spaces: [
            null as CanvasSpace[] | null,
            {
                loadSpaces: async () =>
                    values.currentProjectId ? await loadCanvasSpaces(String(values.currentProjectId)) : [],
            },
        ],
    })),
    reducers({
        isOpen: [
            false,
            {
                openNewCanvasDialog: () => true,
                closeNewCanvasDialog: () => false,
                canvasCreated: () => false,
            },
        ],
        requestedSpaceId: [
            null as string | null,
            {
                openNewCanvasDialog: (_, { spaceId }) => spaceId,
            },
        ],
        chosenSpaceId: [
            null as string | null,
            {
                openNewCanvasDialog: () => null,
                setSelectedSpaceId: (_, { spaceId }) => spaceId,
            },
        ],
        selectedTemplateId: [
            FREEFORM_TEMPLATE_ID as string,
            {
                openNewCanvasDialog: () => FREEFORM_TEMPLATE_ID,
                setSelectedTemplateId: (_, { templateId }) => templateId,
            },
        ],
        creating: [
            false,
            {
                createCanvas: () => true,
                createCanvasFinished: () => false,
            },
        ],
        spacesUnavailable: [
            false,
            {
                loadSpaces: () => false,
                loadSpacesFailure: () => true,
            },
        ],
        // The canvas whose composer takes focus once its scene mounts.
        pendingComposerFocusId: [
            null as string | null,
            {
                canvasCreated: (_, { canvasId }) => canvasId,
                composerFocused: () => null,
            },
        ],
    }),
    selectors({
        templates: [() => [], (): CanvasTemplate[] => CANVAS_TEMPLATES],
        selectedSpaceId: [
            (s) => [s.spaces, s.chosenSpaceId, s.requestedSpaceId],
            (spaces: CanvasSpace[] | null, chosen: string | null, requested: string | null): string | null => {
                if (!spaces) {
                    return null
                }
                const has = (id: string | null): id is string => !!id && spaces.some((space) => space.id === id)
                if (has(chosen)) {
                    return chosen
                }
                if (has(requested)) {
                    return requested
                }
                return (spaces.find((space) => space.system_role === 'personal') ?? spaces[0])?.id ?? null
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        openNewCanvasDialog: () => {
            actions.loadSpaces()
        },
        createCanvas: async () => {
            const spaceId = values.selectedSpaceId
            if (!values.currentProjectId || !spaceId) {
                actions.createCanvasFinished()
                return
            }
            const templateId = values.selectedTemplateId
            posthog.capture(CANVAS_EVENTS.dashboardAction, {
                action_type: 'create',
                surface: 'web_new_canvas_dialog',
                channel_id: spaceId,
                template_id: templateId,
            })
            try {
                const canvas = await canvasesCreate(String(values.currentProjectId), {
                    channel_id: spaceId,
                    name: UNTITLED_CANVAS_NAME,
                    template_id: templateId,
                })
                actions.canvasCreated(canvas.id)
                router.actions.push(urls.canvasDetail(canvas.id))
            } catch (error) {
                lemonToast.error(
                    `Couldn't create the canvas. ${error instanceof Error ? error.message : 'Try again in a moment.'}`
                )
            } finally {
                actions.createCanvasFinished()
            }
        },
    })),
])
