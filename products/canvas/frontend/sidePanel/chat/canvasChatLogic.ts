/**
 * The side panel's Chat tab: the viewer's own run on the canvas, and the composer that
 * continues it. A follow-up goes to the live run, resumes a finished one, or starts the
 * canvas's first run the same way the empty-canvas composer does.
 */
export const canvasChatLogic = kea<canvasChatLogicType>([
    props({} as CanvasChatLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'canvas', 'frontend', 'sidePanel', 'chat', 'canvasChatLogic', key]),
    connect((props: CanvasChatLogicProps) => ({
        values: [
            canvasSceneLogic({ id: props.id }),
            [
                'currentProjectId',
                'view',
                'generationTask',
                'generationStarting',
                'generationError',
                'fixTaskId',
                'agentTurn',
            ],
            canvasHistoryLogic({ id: props.id }),
            ['versions'],
            userLogic,
            ['user'],
        ],
        actions: [
            canvasSceneLogic({ id: props.id }),
            [
                'generateCanvas',
                'generationFinished',
                'canvasUpdated',
                'loadGenerationTaskSuccess',
                'startPolling',
                'requestFixFinished',
            ],
            canvasHistoryLogic({ id: props.id }),
            ['loadVersionsSuccess'],
        ],
    })),
    actions({
        setDraft: (draft: string) => ({ draft }),
        sendMessage: true,
        sendFinished: (error: string | null) => ({ error }),
        taskStarted: (taskId: string) => ({ taskId }),
        /** Loads the viewer's run when it is not the task the scene already loads. */
        syncOwnTask: true,
    }),
    loaders(({ values }) => ({
        // The viewer's run when it is not the canvas's current generation task, which the scene already loads.
        ownTask: [
            null as CanvasGenerationTask | null,
            {
                loadOwnTask: async () => {
                    const taskId = values.chatTaskId
                    return values.currentProjectId && taskId
                        ? await loadCanvasGenerationTask(String(values.currentProjectId), taskId)
                        : null
                },
            },
        ],
    })),
    reducers({
        draft: [
            '',
            {
                setDraft: (_, { draft }) => draft,
                sendFinished: (state, { error }) => (error ? state : ''),
            },
        ],
        sending: [
            false,
            {
                sendMessage: () => true,
                sendFinished: () => false,
            },
        ],
        sendError: [
            null as string | null,
            {
                sendMessage: () => null,
                sendFinished: (_, { error }) => error,
            },
        ],
        startedTaskId: [
            null as string | null,
            {
                taskStarted: (_, { taskId }) => taskId,
            },
        ],
    }),
    selectors({
        chatTaskId: [
            (s) => [s.startedTaskId, s.fixTaskId, s.view, s.generationTask, s.versions, s.user],
            (
                startedTaskId: string | null,
                fixTaskId: string | null,
                view: CanvasViewResponseApi | null,
                generationTask: CanvasGenerationTask | null,
                versions: CanvasVersionApi[],
                user: UserType | null
            ): string | null => {
                const generationTaskId = view?.canvas.generation_task_id ?? null
                return canvasChatTaskId({
                    startedTaskId: startedTaskId ?? fixTaskId,
                    generationTaskId,
                    generationTaskCreatorUuid:
                        generationTask && generationTask.id === generationTaskId
                            ? (generationTask.created_by?.uuid ?? null)
                            : undefined,
                    versions: versions.map((version) => ({
                        taskId: version.task_id,
                        createdByUuid: version.created_by?.uuid ?? null,
                    })),
                    currentUserUuid: user?.uuid,
                })
            },
        ],
        chatTask: [
            (s) => [s.chatTaskId, s.generationTask, s.ownTask],
            (
                chatTaskId: string | null,
                generationTask: CanvasGenerationTask | null,
                ownTask: CanvasGenerationTask | null
            ): CanvasGenerationTask | null =>
                [generationTask, ownTask].find((task) => !!task && task.id === chatTaskId) ?? null,
        ],
        chatRun: [
            (s) => [s.chatTask],
            (chatTask: CanvasGenerationTask | null): CanvasTaskRun | null => chatTask?.latest_run ?? null,
        ],
        chatState: [
            (s) => [s.chatTaskId, s.chatTask, s.sending, s.generationStarting, s.generationError, s.agentTurn],
            (
                chatTaskId: string | null,
                chatTask: CanvasGenerationTask | null,
                sending: boolean,
                generationStarting: boolean,
                generationError: string | null,
                agentTurn: CanvasAgentTurn | null
            ): CanvasChatState =>
                canvasChatState({
                    chatTaskId,
                    chatTask,
                    starting: sending || generationStarting,
                    startError: generationError,
                    agentTurnActive:
                        agentTurn && agentTurn.runId === chatTask?.latest_run?.id ? agentTurn.active : null,
                }),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        syncOwnTask: () => {
            const taskId = values.chatTaskId
            if (taskId !== values.ownTask?.id || taskId === values.generationTask?.id) {
                cache.disposables.dispose('ownTaskPoll')
            }
            if (
                taskId &&
                taskId !== values.generationTask?.id &&
                values.ownTask?.id !== taskId &&
                !values.ownTaskLoading
            ) {
                actions.loadOwnTask()
            }
        },
        loadGenerationTaskSuccess: () => actions.syncOwnTask(),
        loadVersionsSuccess: () => actions.syncOwnTask(),
        requestFixFinished: () => actions.syncOwnTask(),
        taskStarted: () => actions.syncOwnTask(),
        loadOwnTaskSuccess: ({ ownTask }) => {
            cache.disposables.dispose('ownTaskPoll')
            if (
                ownTask &&
                ownTask.id === values.chatTaskId &&
                ownTask.id !== values.generationTask?.id &&
                !isTerminalRunStatus(ownTask.latest_run?.status)
            ) {
                cache.disposables.add(() => {
                    const id = setTimeout(() => actions.loadOwnTask(), CHAT_TASK_POLL_INTERVAL_MS)
                    return () => clearTimeout(id)
                }, 'ownTaskPoll')
            }
        },
        generationFinished: () => {
            if (!values.generationError && values.view?.canvas.generation_task_id) {
                actions.setDraft('')
            }
        },
        sendMessage: async () => {
            const message = values.draft.trim()
            const canvas = values.view?.canvas
            if (!message || !canvas || !values.currentProjectId || values.generationStarting) {
                actions.sendFinished(null)
                return
            }
            const task = values.chatTask
            if (!task) {
                // No run of this viewer's on the canvas yet: build it like the empty-canvas composer does.
                actions.sendFinished(null)
                actions.setDraft(message)
                actions.generateCanvas(message, false, 'web_canvas_side_panel')
                return
            }
            const projectId = String(values.currentProjectId)
            posthog.capture(CANVAS_EVENTS.promptSent, {
                surface: 'web_canvas_side_panel',
                dashboard_id: canvas.id,
                from_suggestion: false,
                prompt_length_chars: message.length,
            })
            try {
                const run = task.latest_run
                if (run && !isTerminalRunStatus(run.status)) {
                    await sendCanvasRunMessage(projectId, task.id, run.id, message)
                } else {
                    const resumed = await resumeCanvasTask(projectId, task.id, {
                        resumeFromRunId: run?.id ?? null,
                        message,
                    })
                    actions.taskStarted(resumed.id)
                    actions.loadGenerationTaskSuccess(resumed)
                    actions.startPolling()
                    // The canvas follows the run that is writing it, so the scene polls its builds.
                    if (canvas.generation_task_id !== resumed.id) {
                        try {
                            actions.canvasUpdated(
                                await canvasesPartialUpdate(projectId, canvas.id, { generation_task_id: resumed.id })
                            )
                        } catch {
                            toast.error({
                                title: 'Your message was sent, but the canvas could not follow the new run.',
                            })
                        }
                    }
                }
                actions.sendFinished(null)
            } catch (error) {
                actions.sendFinished(error instanceof Error ? error.message : 'Try again in a moment.')
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.syncOwnTask()
    }),
])
