const COMMENTS_POLL_INTERVAL_MS = 10_000
// The comments list pages at 100. This many pages covers any real canvas.
const MAX_COMMENT_PAGES = 10

export interface CanvasCommentsLogicProps {
    id: string
}

export type CanvasThreadSource = 'highlight' | 'menu' | 'created'

async function loadAllCanvasComments(canvasId: string): Promise<CommentType[]> {
    // The comments API has no generated client this product can import, so this goes through lib/api.
    const comments: CommentType[] = []
    let page = await api.comments.list({ scope: CANVAS_COMMENT_SCOPE, item_id: canvasId })
    for (let index = 0; index < MAX_COMMENT_PAGES; index++) {
        comments.push(...page.results)
        if (!page.next || index === MAX_COMMENT_PAGES - 1) {
            break
        }
        // nosemgrep: prefer-codegen-api -- The server supplies this pagination URL.
        page = await api.get(page.next)
    }
    return comments
}

