import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import { projectLogic } from 'scenes/projectLogic'

import { hogql } from '~/queries/utils'

import { insightsList } from 'products/product_analytics/frontend/generated/api'

// The same lookups PostHog Desktop's block pickers run: the most common events and property keys, by volume.
const TOP_EVENTS_HOGQL = hogql`SELECT event, count() AS c FROM events WHERE timestamp > now() - INTERVAL 30 DAY GROUP BY event ORDER BY c DESC LIMIT 300`
const TOP_EVENT_PROPERTIES_HOGQL = hogql`SELECT k, count() AS c FROM (SELECT arrayJoin(JSONExtractKeys(properties)) AS k FROM events WHERE timestamp > now() - INTERVAL 7 DAY LIMIT 20000) GROUP BY k ORDER BY c DESC LIMIT 200`
const INSIGHT_SEARCH_DEBOUNCE_MS = 250
const QUERY_TAGS = { productKey: 'canvas', scene: 'Canvas' }

export interface CanvasSavedInsight {
    shortId: string
    name: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface canvasBlockPickersLogicValues {
    currentProjectId: number | null // projectLogic
    insightSearch: string
    savedInsights: CanvasSavedInsight[]
    savedInsightsLoading: boolean
    topEvents: string[] | null
    topEventsError: string | null
    topEventsLoading: boolean
    topProperties: string[] | null
    topPropertiesError: string | null
    topPropertiesLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface canvasBlockPickersLogicActions {
    ensureTopEvents: () => {
        value: true
    }
    ensureTopProperties: () => {
        value: true
    }
    loadSavedInsights: (search: string) => string
    loadSavedInsightsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSavedInsightsSuccess: (
        savedInsights: {
            name: string
            shortId: string
        }[],
        payload?: string
    ) => {
        savedInsights: {
            name: string
            shortId: string
        }[]
        payload?: string
    }
    loadTopEvents: () => any
    loadTopEventsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTopEventsSuccess: (
        topEvents: string[],
        payload?: any
    ) => {
        topEvents: string[]
        payload?: any
    }
    loadTopProperties: () => any
    loadTopPropertiesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTopPropertiesSuccess: (
        topProperties: string[],
        payload?: any
    ) => {
        topProperties: string[]
        payload?: any
    }
    setInsightSearch: (search: string) => {
        search: string
    }
}

export type canvasBlockPickersLogicType = MakeLogicType<canvasBlockPickersLogicValues, canvasBlockPickersLogicActions>

async function firstColumn(query: ReturnType<typeof hogql>, name: string): Promise<string[]> {
    const response = await api.queryHogQL<unknown[][]>(query, { ...QUERY_TAGS, name })
    return (response.results ?? []).map((row) => String(row[0]))
}

/** The options the block inspector's event, property and insight pickers offer. Shared by every canvas. */
export const canvasBlockPickersLogic = kea<canvasBlockPickersLogicType>([
    path(['products', 'canvas', 'frontend', 'sidePanel', 'blocks', 'inspector', 'canvasBlockPickersLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        ensureTopEvents: true,
        ensureTopProperties: true,
        setInsightSearch: (search: string) => ({ search }),
    }),
    loaders(({ values }) => ({
        // Null until loaded, so a picker tells "loading" from "no events yet".
        topEvents: [
            null as string[] | null,
            { loadTopEvents: async () => await firstColumn(TOP_EVENTS_HOGQL, 'canvas_block_picker_events') },
        ],
        topProperties: [
            null as string[] | null,
            {
                loadTopProperties: async () =>
                    await firstColumn(TOP_EVENT_PROPERTIES_HOGQL, 'canvas_block_picker_properties'),
            },
        ],
        savedInsights: [
            [] as CanvasSavedInsight[],
            {
                loadSavedInsights: async (search: string, breakpoint) => {
                    await breakpoint(INSIGHT_SEARCH_DEBOUNCE_MS)
                    if (!values.currentProjectId) {
                        return []
                    }
                    const response = await insightsList(String(values.currentProjectId), {
                        saved: true,
                        basic: true,
                        limit: 200,
                        ...(search.trim() ? { search: search.trim() } : {}),
                    })
                    breakpoint()
                    return response.results.flatMap((insight) =>
                        insight.short_id
                            ? [
                                  {
                                      shortId: insight.short_id,
                                      name: insight.name?.trim() || insight.derived_name?.trim() || 'Untitled insight',
                                  },
                              ]
                            : []
                    )
                },
            },
        ],
    })),
    reducers({
        topEventsError: [
            null as string | null,
            { loadTopEvents: () => null, loadTopEventsFailure: (_, { error }) => error },
        ],
        topPropertiesError: [
            null as string | null,
            { loadTopProperties: () => null, loadTopPropertiesFailure: (_, { error }) => error },
        ],
        insightSearch: [
            '',
            {
                setInsightSearch: (_, { search }) => search,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        ensureTopEvents: () => {
            if (values.topEvents === null && !values.topEventsLoading) {
                actions.loadTopEvents()
            }
        },
        ensureTopProperties: () => {
            if (values.topProperties === null && !values.topPropertiesLoading) {
                actions.loadTopProperties()
            }
        },
        setInsightSearch: ({ search }) => {
            actions.loadSavedInsights(search)
        },
    })),
])
