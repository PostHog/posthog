export interface CanvasHostLogicProps {
    canvasId: string
    /** The canvas's space. Supplied by the host, never by the iframe. */
    spaceId: string | null
    /** The source version the running code came from. */
    sourceVersionId: string | null
    /** Where the canvas is rendered. Defaults to the canvas scene. */
    surface?: CanvasSurface
}

export type CanvasHostPrompt =
    | { kind: 'connector'; id: string; request: CanvasConnectorPermissionRequest }
    | { kind: 'agent-request'; id: string; prompt: string }
    | { kind: 'action'; id: string; request: CanvasActionConfirmation }
    | { kind: 'external-link'; id: string; url: string }

type CanvasHostPromptInput = CanvasHostPrompt extends infer P
    ? P extends CanvasHostPrompt
        ? Omit<P, 'id'>
        : never
    : never

let promptSequence = 0

export function canvasHasUserActivation(): boolean {
    return navigator.userActivation?.isActive === true
}

function openInNewTab(url: string): void {
    window.open(url, '_blank', 'noopener,noreferrer')
}

/** Where a viewer connects a connector provider in the web app. */
export function connectorSettingsUrl(provider: string): string {
    return provider === 'github' ? urls.settings('user-personal-integrations') : urls.settings('mcp-servers')
}

