/**
 * The trusted host around one rendered canvas: it answers the canvas's data requests,
 * asks the viewer before anything that writes, starts work, or leaves the app, and maps
 * the canvas's allowlisted navigation intents to web routes.
 */
export const canvasHostLogic = kea<canvasHostLogicType>([
    props({} as CanvasHostLogicProps),
    key((props) => props.canvasId),
    path((key) => ['products', 'canvas', 'frontend', 'host', 'canvasHostLogic', key]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], teamLogic, ['currentTeam'], userLogic, ['user']],
    })),
    actions({
        enqueuePrompt: (prompt: CanvasHostPrompt) => ({ prompt }),
        respondToPrompt: (id: string, allowed: boolean) => ({ id, allowed }),
        navigate: (intent: CanvasNavIntent) => ({ intent }),
        openExternal: (url: string) => ({ url }),
        canvasRendered: (buildId: string | null) => ({ buildId }),
        canvasErrored: (message: string, buildId: string | null) => ({ message, buildId }),
    }),
    reducers({
        prompts: [
            [] as CanvasHostPrompt[],
            {
                enqueuePrompt: (state, { prompt }) => [...state, prompt],
                respondToPrompt: (state, { id }) => state.filter((prompt) => prompt.id !== id),
            },
        ],
    }),
    selectors({
        activePrompt: [
            (s) => [s.prompts],
            (prompts: CanvasHostPrompt[]): CanvasHostPrompt | null => prompts[0] ?? null,
        ],
    }),
    listeners(({ props, values, cache }) => ({
        respondToPrompt: ({ id, allowed }) => {
            const resolve = (cache.resolvers as Map<string, (allowed: boolean) => void>).get(id)
            cache.resolvers.delete(id)
            resolve?.(allowed)
        },
        openExternal: ({ url }) => {
            // Only a validated GitHub pull request link skips the confirmation.
            if (isSafeGitHubPullRequestUrl(url)) {
                openInNewTab(url)
                return
            }
            void (cache.requestPrompt({ kind: 'external-link', url }) as Promise<boolean>).then((allowed) => {
                if (allowed) {
                    openInNewTab(url)
                }
            })
        },
        navigate: ({ intent }) => {
            switch (intent.target) {
                case 'task':
                    router.actions.push(urls.taskDetail(intent.taskId))
                    break
                case 'canvas':
                    router.actions.push(urls.canvasDetail(intent.dashboardId))
                    break
                case 'new-canvas':
                    router.actions.push(urls.canvasNew(props.spaceId))
                    break
                case 'connect':
                    router.actions.push(connectorSettingsUrl(intent.provider))
                    break
                default:
                    // The web app has no task composer route to prefill, so these are dropped.
                    break
            }
        },
        canvasRendered: ({ buildId }) => {
            posthog.capture(CANVAS_EVENTS.rendered, {
                channel_id: props.spaceId ?? undefined,
                dashboard_id: props.canvasId,
                build_id: buildId ?? undefined,
                surface: props.surface ?? 'web_canvas_scene',
            })
        },
        canvasErrored: ({ message, buildId }) => {
            // A canvas can throw the same error on every render, so each error is reported once per build.
            const errorKey = `${buildId ?? 'draft'}:${message}`
            if (errorKey === cache.lastRuntimeError) {
                return
            }
            cache.lastRuntimeError = errorKey
            const errorType = canvasErrorType(message)
            posthog.capture(CANVAS_EVENTS.runtimeError, {
                channel_id: props.spaceId ?? undefined,
                dashboard_id: props.canvasId,
                build_id: buildId ?? undefined,
                error_type: errorType,
                surface: props.surface ?? 'web_canvas_scene',
            })
            // Files the error in the authoring task's thread so its agent hears about it. Only the
            // class name leaves the browser: the message can carry the viewer's data.
            if (buildId && values.currentProjectId) {
                void canvasesReportErrorCreate(String(values.currentProjectId), props.canvasId, {
                    build_id: buildId,
                    error_type: errorType,
                }).catch(() => {
                    // Reporting is best effort. The header still shows the error and a way to ask for a fix.
                })
            }
        },
    })),
    afterMount((logic) => {
        const { actions, values, cache } = logic
        cache.resolvers = new Map<string, (allowed: boolean) => void>()
        cache.requestPrompt = (input: CanvasHostPromptInput): Promise<boolean> =>
            new Promise((resolve) => {
                const id = `canvas-prompt-${++promptSequence}`
                cache.resolvers.set(id, resolve)
                actions.enqueuePrompt({ ...input, id } as CanvasHostPrompt)
            })
        cache.bridge = new CanvasDataBridge(
            () => ({
                projectId: String(values.currentProjectId ?? ''),
                // Read through the logic so a new source version is picked up without a remount.
                canvasId: logic.props.canvasId,
                sourceVersionId: logic.props.sourceVersionId,
                captureToken: values.currentTeam?.api_token ?? null,
                distinctId: values.user?.distinct_id ?? null,
            }),
            {
                confirmAction: (request) => cache.requestPrompt({ kind: 'action', request }),
                confirmAgentRequest: (prompt) => cache.requestPrompt({ kind: 'agent-request', prompt }),
                requestConnectorPermission: (request) => cache.requestPrompt({ kind: 'connector', request }),
                hasUserActivation: canvasHasUserActivation,
            }
        )
    }),
    beforeUnmount(({ cache }) => {
        // A canvas waiting on the viewer gets a denial rather than a promise that never settles.
        for (const resolve of (cache.resolvers as Map<string, (allowed: boolean) => void>).values()) {
            resolve(false)
        }
        cache.resolvers.clear()
    }),
])

/** Resolves a data request through the host's bridge. The logic must be mounted. */
export function handleCanvasDataRequest(
    logic: ReturnType<typeof canvasHostLogic>,
    method: string,
    payload: unknown
): Promise<unknown> {
    return (logic.cache.bridge as CanvasDataBridge).handle(method, payload)
}
