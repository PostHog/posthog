function besideSelection(selection: CanvasEditSelection, blockType: string): SourceDropTarget {
    const source = selection.source as SourceRange
    const pairs = selection.blockType === blockType && SIDE_BY_SIDE_BLOCKS.has(blockType)
    const grid = selection.layout.grid
    if (!pairs && grid) {
        return { ...grid, place: 'after' }
    }
    if (!pairs) {
        return { ...source, place: 'after' }
    }
    if (!selection.layout.inGrid) {
        return { ...source, place: 'right' }
    }
    const grow = selection.layout.grow
    return grow ? { ...source, place: 'after', grow } : { ...source, place: 'after' }
}

function saveErrorMessage(error: unknown): string {
    const data = (error as { data?: { detail?: string; diagnostics?: CanvasDiagnosticApi[] } } | null)?.data
    const diagnostic = data?.diagnostics?.find((item) => item.severity === 'error')
    if (diagnostic) {
        return diagnostic.path ? `${diagnostic.path}: ${diagnostic.message}` : diagnostic.message
    }
    return data?.detail || (error instanceof Error ? error.message : String(error))
}

