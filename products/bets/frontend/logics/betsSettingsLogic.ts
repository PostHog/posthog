import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import type { Breadcrumb } from '~/types'

import { insightsList } from 'products/product_analytics/frontend/generated/api'
import type { InsightApi } from 'products/product_analytics/frontend/generated/api.schemas'

import { betsList, betsSettingsPartialUpdate } from '../generated/api'
import type { BetsOverviewApi, BetsStepModelWriteApi, ModelStepEnumApi } from '../generated/api.schemas'
import { errorMessage } from '../lib/format'
import { betsBreadcrumbs } from '../lib/navigation'
import { betsLogic } from './betsLogic'

export type MinRunUnit = 'days' | 'hours'

function minRunUnit(hours: number): MinRunUnit {
    return hours % 24 === 0 ? 'days' : 'hours'
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface betsSettingsLogicValues {
    currentProjectId: number | string // teamLogic
    breadcrumbs: Breadcrumb[]
    budget: number
    busy: boolean
    failed: boolean
    goalConfirmHours: number
    insight: string
    insights: InsightApi[]
    insightsLoading: boolean
    mdePercent: number
    message: string
    minRun: number
    minRunUnit: MinRunUnit
    overview: BetsOverviewApi | null
    overviewLoading: boolean
    stepModels: Partial<Record<ModelStepEnumApi, BetsStepModelWriteApi>>
}

