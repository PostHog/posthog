export type betsSettingsLogicType = MakeLogicType<betsSettingsLogicValues, betsSettingsLogicActions>

export const betsSettingsLogic = kea<betsSettingsLogicType>([
    path(['products', 'bets', 'betsSettingsLogic']),
    connect({ values: [teamLogic, ['currentProjectId']] }),
    selectors({ breadcrumbs: [() => [], (): Breadcrumb[] => betsBreadcrumbs('settings')] }),
    actions({
        setBudget: (budget: number) => ({ budget }),
        setInsight: (insight: string) => ({ insight }),
        setMinRun: (value: number) => ({ value }),
        setMinRunUnit: (unit: MinRunUnit) => ({ unit }),
        setMdePercent: (percent: number) => ({ percent }),
        setGoalConfirmHours: (hours: number) => ({ hours }),
        setStepModel: (step: ModelStepEnumApi, patch: Partial<BetsStepModelWriteApi>) => ({ step, patch }),
        save: true,
        setBusy: (busy: boolean) => ({ busy }),
        setMessage: (message: string, failed: boolean) => ({ message, failed }),
    }),
    loaders(({ values }) => ({
        overview: [
            null as BetsOverviewApi | null,
            { loadSettings: async () => await betsList(String(values.currentProjectId)) },
        ],
        insights: [
            [] as InsightApi[],
            {
                loadInsights: async () =>
                    (await insightsList(String(values.currentProjectId), { basic: true, saved: true, limit: 100 }))
                        .results,
            },
        ],
    })),
    reducers({
        budget: [
            0,
            {
                setBudget: (_, { budget }) => budget,
                loadSettingsSuccess: (_, { overview }) => overview.settings.budget_cents / 100,
            },
        ],
        insight: [
            '',
            {
                setInsight: (_, { insight }) => insight,
                loadSettingsSuccess: (_, { overview }) => overview.settings.north_star_insight,
            },
        ],
        minRun: [
            0,
            {
                setMinRun: (_, { value }) => value,
                loadSettingsSuccess: (_, { overview }) => {
                    const hours = overview.settings.min_run_hours
                    return minRunUnit(hours) === 'days' ? hours / 24 : hours
                },
            },
        ],
        minRunUnit: [
            'days' as MinRunUnit,
            {
                setMinRunUnit: (_, { unit }) => unit,
                loadSettingsSuccess: (_, { overview }) => minRunUnit(overview.settings.min_run_hours),
            },
        ],
        mdePercent: [
            30,
            {
                setMdePercent: (_, { percent }) => percent,
                loadSettingsSuccess: (_, { overview }) => overview.settings.mde_percent,
            },
        ],
        goalConfirmHours: [
            72,
            {
                setGoalConfirmHours: (_, { hours }) => hours,
                loadSettingsSuccess: (_, { overview }) => overview.settings.goal_confirm_hours,
            },
        ],
        stepModels: [
            {} as Partial<Record<ModelStepEnumApi, BetsStepModelWriteApi>>,
            {
                setStepModel: (state, { step, patch }) => ({ ...state, [step]: { ...state[step]!, ...patch } }),
                loadSettingsSuccess: (_, { overview }) =>
                    Object.fromEntries(
                        overview.settings.models.map((item) => [
                            item.step,
                            { model: item.model, reasoning_effort: item.reasoning_effort, billing: item.billing },
                        ])
                    ),
            },
        ],
        busy: [false, { setBusy: (_, { busy }) => busy }],
        message: [
            '',
            {
                setMessage: (_, { message }) => message,
                loadSettings: () => '',
                loadSettingsFailure: (_, { error }) => error,
                loadInsightsFailure: (_, { error }) => error,
            },
        ],
        failed: [
            false,
            {
                setMessage: (_, { failed }) => failed,
                loadSettings: () => false,
                loadSettingsFailure: () => true,
                loadInsightsFailure: () => true,
            },
        ],
    }),
    listeners(({ values, actions }) => ({
        save: async () => {
            if (values.busy) {
                return
            }
            actions.setBusy(true)
            actions.setMessage('', false)
            try {
                await betsSettingsPartialUpdate(String(values.currentProjectId), {
                    budget_cents: Math.round(values.budget * 100),
                    north_star_insight: values.insight,
                    step_models: values.stepModels,
                    min_run_hours: values.minRunUnit === 'days' ? values.minRun * 24 : values.minRun,
                    mde_percent: values.mdePercent,
                    goal_confirm_hours: values.goalConfirmHours,
                })
                betsLogic.actions.loadOverview()
                actions.loadSettingsSuccess(await betsList(String(values.currentProjectId)))
                actions.setMessage('Settings saved.', false)
            } catch (error) {
                actions.setMessage(errorMessage(error), true)
            } finally {
                actions.setBusy(false)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSettings()
        actions.loadInsights()
    }),
])
