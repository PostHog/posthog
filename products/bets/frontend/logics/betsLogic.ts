export type betsLogicType = MakeLogicType<betsLogicValues, betsLogicActions, Record<string, any>, betsLogicMeta>

export const betsLogic = kea<betsLogicType>([
    path(['products', 'bets', 'betsLogic']),
    connect({ values: [teamLogic, ['currentProjectId'], router, ['location'], userLogic, ['user']] }),
    actions({
        setSearch: (search: string) => ({ search }),
        setStatus: (status: string) => ({ status }),
        setArea: (area: string) => ({ area }),
        setOwner: (owner: string) => ({ owner }),
        updateBetEntry: (bet: BetsEntryApi) => ({ bet }),
    }),
    loaders(({ values }) => ({
        overview: [
            null as BetsOverviewApi | null,
            {
                loadOverview: async (refresh = false) => await betsList(String(values.currentProjectId), { refresh }),
                updateBetEntry: ({ bet }) =>
                    values.overview && {
                        ...values.overview,
                        bets: values.overview.bets.map((entry) =>
                            entry.id === bet.id
                                ? (Object.fromEntries(
                                      Object.keys(entry).map((key) => [key, bet[key as keyof BetsEntryApi]])
                                  ) as unknown as BetsEntryApi)
                                : entry
                        ),
                    },
            },
        ],
    })),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        status: ['all', { setStatus: (_, { status }) => status }],
        area: ['', { setArea: (_, { area }) => area }],
        owner: ['', { setOwner: (_, { owner }) => owner }],
        error: [null as string | null, { loadOverview: () => null, loadOverviewFailure: (_, { error }) => error }],
    }),
    selectors({
        breadcrumbs: [
            () => [router.selectors.location],
            (location: { hash: string; pathname: string; search: string }): Breadcrumb[] =>
                betsBreadcrumbs(removeProjectIdIfPresent(location.pathname) === urls.betsAll() ? 'all' : 'overview'),
        ],
        areas: [
            (s) => [s.overview],
            (overview: BetsOverviewApi | null): string[] =>
                [...new Set(overview?.bets.map((bet) => bet.area).filter(Boolean) ?? [])].sort(),
        ],
        owners: [
            (s) => [s.overview, s.user],
            (overview: BetsOverviewApi | null, user: { id: number } | null): { id: number; name: string }[] =>
                [...new Map((overview?.bets ?? []).map((bet) => [bet.owner.user_id, bet.owner.name])).entries()]
                    .filter(([id]) => id !== user?.id)
                    .map(([id, name]) => ({ id, name }))
                    .sort((a, b) => a.name.localeCompare(b.name)),
        ],
        filteredBets: [
            (s) => [s.overview, s.search, s.status, s.area, s.owner, s.user],
            (
                overview: BetsOverviewApi | null,
                search: string,
                status: string,
                area: string,
                owner: string,
                user: { id: number } | null
            ): BetsEntryApi[] => {
                const ownerId = owner === 'me' ? user?.id : owner ? Number(owner) : null
                return (overview?.bets ?? []).filter(
                    (bet) =>
                        (!search || `${bet.title} ${bet.goal_metric}`.toLowerCase().includes(search.toLowerCase())) &&
                        (!area || bet.area === area) &&
                        (ownerId == null || bet.owner.user_id === ownerId) &&
                        (status === 'all' || (status === 'open' ? bet.status !== 'closed' : bet.status === status))
                )
            },
        ],
        recentBets: [
            (s) => [s.overview],
            (overview: BetsOverviewApi | null): BetsEntryApi[] =>
                (overview?.bets ?? [])
                    .filter((bet) => bet.status !== 'closed')
                    .sort(
                        (a, b) =>
                            Number(ACTIVE_STATUSES.has(b.status)) - Number(ACTIVE_STATUSES.has(a.status)) ||
                            Date.parse(b.updated_at) - Date.parse(a.updated_at)
                    ),
        ],
    }),
    listeners(({ actions, values }) => ({
        [router.actionTypes.locationChanged]: () => {
            if ([urls.bets(), urls.betsAll()].includes(removeProjectIdIfPresent(values.location.pathname))) {
                actions.loadOverview()
            }
        },
    })),
    afterMount(({ actions, values, cache }) => {
        actions.loadOverview()
        cache.disposables.add(() => {
            const timer = window.setInterval(() => {
                if (!document.hidden && !values.overviewLoading && !values.error) {
                    actions.loadOverview()
                }
            }, REFRESH_INTERVAL_MS)
            return () => window.clearInterval(timer)
        })
    }),
])
