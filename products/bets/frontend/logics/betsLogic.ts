import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import type { LocationChangedPayload } from 'kea-router/lib/types'

import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import type { Breadcrumb } from '~/types'

import { betsList } from '../generated/api'
import type { BetsEntryApi, BetsOverviewApi } from '../generated/api.schemas'
import { betsBreadcrumbs } from '../lib/navigation'

const REFRESH_INTERVAL_MS = 15000
const ACTIVE_STATUSES = new Set<string>(['setting_up', 'running'])

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface betsLogicValues {
    location: {
        pathname: string
        search: string
        hash: string
    } // router
    currentProjectId: number | string // teamLogic
    area: string
    areas: string[]
    breadcrumbs: Breadcrumb[]
    error: string | null
    filteredBets: BetsEntryApi[]
    overview: BetsOverviewApi | null
    overviewLoading: boolean
    recentBets: BetsEntryApi[]
    search: string
    status: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface betsLogicActions {
    loadOverview: (refresh?: boolean) => any
    loadOverviewFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadOverviewSuccess: (
        overview: BetsOverviewApi,
        payload?: any
    ) => {
        overview: BetsOverviewApi
        payload?: any
    }
    setArea: (area: string) => {
        area: string
    }
    setSearch: (search: string) => {
        search: string
    }
    setStatus: (status: string) => {
        status: string
    }
}

