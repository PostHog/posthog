export type betFormLogicType = MakeLogicType<
    betFormLogicValues,
    betFormLogicActions,
    betFormLogicProps,
    betFormLogicMeta
>

export const betFormLogic = kea<betFormLogicType>([
    props({ id: 'new' } as { id: string }),
    key((props) => props.id),
    path((key) => ['products', 'bets', 'betFormLogic', key]),
    connect({
        values: [teamLogic, ['currentProjectId'], betsLogic, ['overview']],
    }),
    actions({
        change: (patch: Partial<BetsWriteApi>) => ({ patch }),
        selectPrimaryInsight: (insight: string) => ({ insight }),
        submit: true,
        setBusy: (busy: boolean) => ({ busy }),
        setError: (error: string | null) => ({ error }),
        addOwnerIdea: true,
        changeOwnerIdea: (index: number, title: string) => ({ index, title }),
        removeOwnerIdea: (index: number) => ({ index }),
    }),
    loaders(({ values, props }) => ({
        insights: [
            [] as InsightApi[],
            {
                loadInsights: async () =>
                    (await insightsList(String(values.currentProjectId), { basic: true, saved: true, limit: 100 }))
                        .results,
            },
        ],
        existing: [
            null as BetsDetailApi | null,
            { loadExisting: async () => await betsRetrieve(String(values.currentProjectId), props.id) },
        ],
    })),
    reducers({
        form: [
            empty,
            {
                change: (state, { patch }) => ({ ...state, ...patch }),
                loadExistingSuccess: (_, { existing }: { existing: BetsDetailApi }) => ({
                    title: existing.title,
                    statement: existing.statement,
                    audience: existing.audience,
                    area: existing.area,
                    repository: existing.repository,
                    goal_metric: existing.goal_metric,
                    goal_insight: existing.goal_insight,
                    secondary_metrics: existing.secondary_metrics,
                    target: existing.target === null ? '' : String(Number(existing.target)),
                    direction: existing.direction === 'decrease' ? ('decrease' as const) : ('increase' as const),
                    unit: existing.unit,
                    budget_cents: existing.money.allocated_cents,
                }),
            },
        ],
        ownerIdeas: [
            [''] as string[],
            {
                addOwnerIdea: (state) => (state.length < MAX_OWNER_IDEAS ? [...state, ''] : state),
                changeOwnerIdea: (state, { index, title }) =>
                    state.map((idea, position) => (position === index ? title : idea)),
                removeOwnerIdea: (state, { index }) => {
                    const next = state.filter((_, position) => position !== index)
                    return next.length ? next : ['']
                },
            },
        ],
        busy: [false, { setBusy: (_, { busy }) => busy }],
        error: [
            null as string | null,
            {
                setError: (_, { error }) => error,
                loadExistingFailure: (_, { error }) => error,
                loadInsightsFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors(({ props }) => ({
        budgetLimitCents: [
            (s) => [s.overview, s.existing],
            (overview: BetsOverviewApi | null, existing: BetsDetailApi | null): number | null =>
                overview ? Math.max(0, overview.unallocated_cents) + (existing?.money.allocated_cents ?? 0) : null,
        ],
        breadcrumbs: [
            (s) => [s.existing],
            (existing: BetsDetailApi | null): Breadcrumb[] =>
                betsBreadcrumbs(props.id === 'new' ? 'new' : 'edit', { id: props.id, title: existing?.title ?? 'Bet' }),
        ],
    })),
    listeners(({ values, actions, props, cache }) => ({
        selectPrimaryInsight: ({ insight }) => {
            const item = values.insights.find((entry) => entry.short_id === insight)
            actions.change({
                goal_insight: insight,
                ...(!values.form.goal_metric && item ? { goal_metric: item.name || item.derived_name || '' } : {}),
                secondary_metrics: values.form.secondary_metrics?.filter((metric) => metric.insight !== insight),
            })
        },
        submit: async () => {
            if (values.busy) {
                return
            }
            actions.setBusy(true)
            actions.setError(null)
            cache.operationId ??= crypto.randomUUID()
            try {
                const bet =
                    props.id === 'new'
                        ? await betsCreate(String(values.currentProjectId), {
                              ...values.form,
                              ideas: values.ownerIdeas.map((idea) => idea.trim()).filter(Boolean),
                              operation_id: cache.operationId,
                          })
                        : await betsPartialUpdate(String(values.currentProjectId), props.id, values.form)
                betsLogic.actions.loadOverview()
                router.actions.replace(urls.bet(bet.id))
            } catch (error) {
                actions.setError(errorMessage(error))
            } finally {
                actions.setBusy(false)
            }
        },
    })),
    afterMount(({ actions, props }) => {
        actions.loadInsights()
        if (props.id !== 'new') {
            actions.loadExisting()
        }
    }),
])
