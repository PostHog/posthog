import type { InsightApi } from 'products/product_analytics/frontend/generated/api.schemas'

import { betsCreate, betsPartialUpdate, betsRetrieve } from '../generated/api'
import type { BetsDetailApi, BetsOverviewApi, BetsWriteApi } from '../generated/api.schemas'
import { errorMessage } from '../lib/format'
import { betsBreadcrumbs } from '../lib/navigation'
import { betsLogic } from './betsLogic'

