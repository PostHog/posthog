function sidebarFields(bet: BetsEntryApi | BetsDetailApi): string {
    return JSON.stringify([
        bet.title,
        bet.status,
        bet.state.headline,
        bet.money,
        bet.metric.current,
        bet.spend_pending,
        bet.updated_at,
    ])
}

