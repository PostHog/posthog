export const betLogic = kea<betLogicType>([
    props({} as { id: string }),
    key((props) => props.id),
    path((key) => ['products', 'bets', 'betLogic', key]),
    connect({
        values: [teamLogic, ['currentProjectId'], betsLogic, ['overview']],
        actions: [
            betsLogic,
            ['loadOverview', 'updateBetEntry'],
            maxGlobalLogic,
            ['setPhaiViewMode'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setHistoryExpanded', 'setActiveCreation'],
            sidePanelStateLogic,
            ['openSidePanel', 'setSidePanelOptions'],
        ],
    }),
    actions({
        setExpandedWork: (workId: string | null) => ({ workId }),
        openTask: (taskId: string) => ({ taskId }),
        setBet: (bet: BetsDetailApi) => ({ bet }),
        setBusy: (operation: string | null) => ({ operation }),
        setError: (error: string | null) => ({ error }),
        changeStatus: (status: BetsStatusApi['status']) => ({ status }),
        work: (payload: BetsWorkActionApi) => ({ payload }),
        buildIdea: (workId: string) => ({ workId }),
        dismissIdea: (workId: string, reason: string) => ({ workId, reason }),
        addIdea: (title: string) => ({ title }),
        openDismiss: (workId: string | null) => ({ workId }),
        setDismissReason: (reason: string) => ({ reason }),
        setAddingIdea: (adding: boolean) => ({ adding }),
        setIdeaDraft: (title: string) => ({ title }),
        setIdeaError: (error: string | null) => ({ error }),
        toggleIdeaReport: (workId: string) => ({ workId }),
        setExpandedIdea: (workId: string | null) => ({ workId }),
        resetIdeas: true,
        showAllEvidence: (workId: string) => ({ workId }),
        setLaterOpen: (open: boolean) => ({ open }),
        setDismissedOpen: (open: boolean) => ({ open }),
        editPlan: (workId: string, plan: BetsPlanApi, field: PlanField, value: string) => ({
            workId,
            plan,
            field,
            value,
        }),
        extendWork: (workId: string) => ({ workId }),
        openBuild: (workId: string | null) => ({ workId }),
        openStop: (workId: string | null) => ({ workId }),
        stopWork: (workId: string) => ({ workId }),
        runStateAction: (action: BetsStateActionApi) => ({ action }),
    }),
    loaders(({ props, values }) => ({
        pullRequestTitles: [
            {} as Record<string, string>,
            {
                loadPullRequestTitles: async (ids: string[]) => {
                    try {
                        const result = await tasksPullRequestTitlesCreate(String(values.currentProjectId), { ids })
                        return { ...values.pullRequestTitles, ...result.titles }
                    } catch {
                        return values.pullRequestTitles
                    }
                },
            },
        ],
        activity: [
            null as BetsActivityApi[] | null,
            { loadActivity: async () => await betsActivityList(String(values.currentProjectId), props.id) },
        ],
        bet: [
            null as BetsDetailApi | null,
            { loadBet: async () => await betsRetrieve(String(values.currentProjectId), props.id) },
        ],
    })),
    reducers({
        expandedWork: [null as string | null, { setExpandedWork: (_, { workId }) => workId }],
        workToggled: [false, { setExpandedWork: () => true }],
        activityError: [
            null as string | null,
            { loadActivity: () => null, loadActivityFailure: (_, { error }) => error },
        ],
        bet: [null as BetsDetailApi | null, { setBet: (_, { bet }) => bet }],
        busyOperation: [null as string | null, { setBusy: (_, { operation }) => operation }],
        error: [
            null as string | null,
            { setError: (_, { error }) => error, loadBet: () => null, loadBetFailure: (_, { error }) => error },
        ],
        ideaError: [
            null as string | null,
            {
                setIdeaError: (_, { error }) => error,
                openDismiss: () => null,
                openBuild: () => null,
                setAddingIdea: () => null,
            },
        ],
        dismissingIdea: [
            null as string | null,
            { openDismiss: (_, { workId }) => workId, setAddingIdea: (state, { adding }) => (adding ? null : state) },
        ],
        dismissReason: ['', { setDismissReason: (_, { reason }) => reason, openDismiss: () => '' }],
        addingIdea: [
            false,
            { setAddingIdea: (_, { adding }) => adding, openDismiss: (state, { workId }) => (workId ? false : state) },
        ],
        ideaDraft: [
            '',
            { setIdeaDraft: (_, { title }) => title, setAddingIdea: (state, { adding }) => (adding ? state : '') },
        ],
        expandedIdeas: [
            [] as string[],
            {
                toggleIdeaReport: (state, { workId }) =>
                    state.includes(workId) ? state.filter((id) => id !== workId) : [...state, workId],
            },
        ],
        laterOpen: [false, { setLaterOpen: (_, { open }) => open, resetIdeas: () => false }],
        expandedIdea: [null as string | null, { setExpandedIdea: (_, { workId }) => workId, resetIdeas: () => null }],
        ideaToggled: [false, { setExpandedIdea: () => true, resetIdeas: () => false }],
        allEvidenceShown: [
            [] as string[],
            { showAllEvidence: (state, { workId }) => (state.includes(workId) ? state : [...state, workId]) },
        ],
        dismissedOpen: [false, { setDismissedOpen: (_, { open }) => open }],
        planDrafts: [
            {} as Record<string, PlanDraft>,
            {
                editPlan: (state, { workId, plan, field, value }) => ({
                    ...state,
                    [workId]: editDraft(state[workId] ?? initialDraft(plan), plan, field, value),
                }),
                resetIdeas: () => ({}),
            },
        ],
        stoppingWork: [null as string | null, { openStop: (_, { workId }) => workId }],
        buildDialogIdea: [null as string | null, { openBuild: (state, { workId }) => workId ?? state }],
        buildDialogOpen: [false, { openBuild: (_, { workId }) => workId !== null, resetIdeas: () => false }],
    }),
    selectors(({ props }) => ({
        [SIDE_PANEL_CONTEXT_KEY]: [
            () => [],
            (): SidePanelSceneContext => ({ activity_scope: ActivityScope.BET, activity_item_id: props.id }),
        ],
        busy: [(s) => [s.busyOperation], (operation: string | null): boolean => operation !== null],
        breadcrumbs: [
            (s) => [s.bet],
            (bet: BetsDetailApi | null): Breadcrumb[] =>
                betsBreadcrumbs('detail', { id: props.id, title: bet?.title ?? 'Bet' }),
        ],
        waitingIdeas: [
            (s) => [s.bet],
            (bet: BetsDetailApi | null): BetsWorkApi[] => (bet ? currentWaitingIdeas(bet) : []),
        ],
        dismissedIdeas: [
            (s) => [s.bet],
            (bet: BetsDetailApi | null): BetsWorkApi[] => (bet ? currentDismissedIdeas(bet) : []),
        ],
        ideaInProgress: [
            (s) => [s.bet],
            (bet: BetsDetailApi | null): BetsWorkApi | null => (bet ? currentIdeaInProgress(bet) : null),
        ],
        openIdea: [
            (s) => [s.expandedIdea, s.ideaToggled, s.waitingIdeas, s.ideaInProgress],
            (
                expandedIdea: string | null,
                ideaToggled: boolean,
                waitingIdeas: BetsWorkApi[],
                ideaInProgress: BetsWorkApi | null
            ): string | null => (ideaToggled || ideaInProgress ? expandedIdea : firstSupportedIdea(waitingIdeas)),
        ],
        openWork: [
            (s) => [s.expandedWork, s.workToggled, s.bet],
            (expandedWork: string | null, workToggled: boolean, bet: BetsDetailApi | null): string | null =>
                workToggled
                    ? expandedWork
                    : (bet?.work.find((item) => item.stage === 'live' && item.plan.proposed_days)?.id ?? null),
        ],
        ideaPlans: [
            (s) => [s.bet, s.planDrafts],
            (bet: BetsDetailApi | null, planDrafts: Record<string, PlanDraft>): Record<string, IdeaPlan> =>
                Object.fromEntries(
                    (bet?.work ?? [])
                        .filter((item) => item.kind === 'idea' && item.stage === 'proposed' && plannable(item.plan))
                        .map((item) => [item.id, ideaPlan(item.plan, planDrafts[item.id])])
                ),
        ],
        buildDisabledReason: [
            (s) => [s.bet],
            (bet: BetsDetailApi | null): string | null => bet?.state.build_blocked || null,
        ],
    })),
    listeners(({ actions, values, props, cache }) => {
        const perform = async (
            operation: string,
            request: () => Promise<BetsDetailApi>,
            setError: (error: string | null) => void = actions.setError
        ): Promise<boolean> => {
            if (values.busy) {
                return false
            }
            actions.setBusy(operation)
            setError(null)
            try {
                actions.setBet(await request())
                actions.loadActivity()
                actions.loadOverview()
                return true
            } catch (error) {
                setError(errorMessage(error))
                return false
            } finally {
                actions.setBusy(null)
            }
        }
        return {
            openBuild: ({ workId }) => {
                if (workId) {
                    posthog.capture('bet build dialog opened', { bet_id: props.id, work_id: workId })
                }
            },
            loadBetSuccess: ({ bet }) => {
                const entry = values.overview?.bets.find((item) => item.id === bet.id)
                if (entry && sidebarFields(entry) !== sidebarFields(bet)) {
                    actions.updateBetEntry(bet)
                }
                if (!values.activityLoading && Date.now() - (cache.activityReadAt ?? 0) >= 30000) {
                    cache.activityReadAt = Date.now()
                    actions.loadActivity()
                }
                const ids = bet.work
                    .filter((item) => item.task_id && item.pr_url)
                    .map((item) => item.task_id!)
                    .slice(0, 30)
                const key = bet.work
                    .filter((item) => ids.includes(item.task_id ?? ''))
                    .map((item) => `${item.task_id}:${item.pr_url}`)
                    .join('|')
                if (key && cache.pullRequestTaskIds !== key) {
                    cache.pullRequestTaskIds = key
                    actions.loadPullRequestTitles(ids)
                }
            },
            openTask: async ({ taskId }) => {
                if (values.busy) {
                    return
                }
                actions.setBusy(`open-task:${taskId}`)
                actions.setError(null)
                try {
                    const taskRunId = (await tasksRetrieve(String(values.currentProjectId), taskId)).latest_run?.id
                    if (!taskRunId) {
                        actions.setError('This task has not started yet. Its progress will appear here when it starts.')
                        return
                    }
                    prefetchRunStream(taskId, taskRunId, null)
                    actions.setPhaiViewMode('new')
                    actions.setHistoryExpanded(false)
                    actions.setSidePanelOptions(null)
                    actions.openSidePanel(SidePanelTab.Max)
                    actions.setActiveCreation({
                        taskId,
                        runId: taskRunId,
                        streamKey: taskRunId,
                    })
                } catch (error) {
                    actions.setError(errorMessage(error))
                } finally {
                    actions.setBusy(null)
                }
            },
            changeStatus: async ({ status }) => {
                await perform(`status:${status}`, () =>
                    betsStatusCreate(String(values.currentProjectId), props.id, { status })
                )
            },
            work: async ({ payload }) => {
                await perform(`work:${payload.work_id}:${payload.action}`, () =>
                    betsWorkCreate(String(values.currentProjectId), props.id, payload)
                )
            },
            buildIdea: async ({ workId }) => {
                const plan = values.ideaPlans[workId]
                if (plan && !plan.input) {
                    return
                }
                const done = await perform(
                    `work:${workId}:build`,
                    () =>
                        betsWorkCreate(String(values.currentProjectId), props.id, {
                            work_id: workId,
                            action: 'build',
                            ...(plan?.input ? { plan: plan.input } : {}),
                        }),
                    actions.setIdeaError
                )
                if (done) {
                    actions.resetIdeas()
                }
            },
            extendWork: ({ workId }) => {
                actions.work({ work_id: workId, action: 'extend' })
            },
            stopWork: async ({ workId }) => {
                const done = await perform(`work:${workId}:drop`, () =>
                    betsWorkCreate(String(values.currentProjectId), props.id, { work_id: workId, action: 'drop' })
                )
                if (done) {
                    actions.openStop(null)
                }
            },
            runStateAction: ({ action }) => {
                if (action.kind === 'ideas') {
                    document.getElementById('bet-ideas')?.scrollIntoView({ behavior: 'smooth' })
                    actions.setAddingIdea(!values.bet?.state.ready_ideas)
                } else if (!action.work_id) {
                    return
                } else if (action.work_action === 'drop') {
                    actions.setExpandedWork(action.work_id)
                    actions.openStop(action.work_id)
                } else if (action.work_action) {
                    actions.work({ work_id: action.work_id, action: action.work_action })
                } else {
                    actions.setExpandedWork(action.work_id)
                }
            },
            dismissIdea: async ({ workId, reason }) => {
                const done = await perform(
                    `work:${workId}:dismiss`,
                    () =>
                        betsWorkCreate(String(values.currentProjectId), props.id, {
                            work_id: workId,
                            action: 'dismiss',
                            reason: reason.trim(),
                        }),
                    actions.setIdeaError
                )
                if (done) {
                    actions.openDismiss(null)
                }
            },
            addIdea: async ({ title }) => {
                const done = await perform(
                    'add-idea',
                    () => betsIdeasCreate(String(values.currentProjectId), props.id, { title: title.trim() }),
                    actions.setIdeaError
                )
                if (done) {
                    actions.setAddingIdea(false)
                }
            },
        }
    }),
    afterMount(({ actions, values, cache }) => {
        actions.loadBet()
        let lastReadAt = Date.now()
        cache.disposables.add(() => {
            const timer = window.setInterval(() => {
                if (!document.hidden && !values.betLoading && !values.busy) {
                    const running = values.bet?.work.some((item) =>
                        ['queued', 'in_progress'].includes(item.task_status)
                    )
                    if (running || Date.now() - lastReadAt >= 15000) {
                        lastReadAt = Date.now()
                        actions.loadBet()
                    }
                }
            }, 3000)
            return () => window.clearInterval(timer)
        })
    }),
])
