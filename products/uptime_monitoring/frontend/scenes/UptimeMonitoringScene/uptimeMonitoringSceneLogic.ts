export const uptimeMonitoringSceneLogic = kea<uptimeMonitoringSceneLogicType>([
    path([
        'products',
        'uptime_monitoring',
        'frontend',
        'scenes',
        'UptimeMonitoringScene',
        'uptimeMonitoringSceneLogic',
    ]),

    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
        actions: [featureFlagLogic, ['setFeatureFlags']],
    })),

    actions({
        openCreateModal: true,
        closeCreateModal: true,
        confirmDeleteMonitor: (monitor: UptimeMonitorApi) => ({ monitor }),
    }),

    loaders(({ values }) => ({
        monitors: [
            null as UptimeMonitorApi[] | null,
            {
                loadMonitors: async (_: void, breakpoint) => {
                    const response = await uptimeMonitorsList(projectId(), { limit: LIST_LIMIT })
                    // A newer load started while this one ran, so this response may miss a monitor created since.
                    breakpoint()
                    return response.results
                },
                deleteMonitor: async (monitor: UptimeMonitorApi) => {
                    await uptimeMonitorsDestroy(projectId(), monitor.id)
                    lemonToast.success('Monitor deleted')
                    return (values.monitors ?? []).filter((m) => m.id !== monitor.id)
                },
            },
        ],
    })),

    reducers({
        isCreateModalOpen: [
            false,
            {
                openCreateModal: () => true,
                closeCreateModal: () => false,
            },
        ],
    }),

    forms(({ actions, values }) => ({
        newMonitor: {
            defaults: NEW_MONITOR_DEFAULTS,
            errors: ({ name, url }) => ({
                name: !name.trim() ? 'Enter a name' : undefined,
                url: !isHttpUrl(url) ? 'Enter a URL that starts with http:// or https://' : undefined,
            }),
            submit: async (form) => {
                const created = await uptimeMonitorsCreate(projectId(), { ...form, name: form.name.trim() })
                // Without a settled list there is nothing safe to prepend to, so fetch it again.
                if (values.monitors === null || values.monitorsLoading) {
                    actions.loadMonitors()
                } else {
                    actions.loadMonitorsSuccess([created, ...values.monitors])
                }
            },
        },
    })),

    listeners(({ actions, values }) => ({
        setFeatureFlags: () => {
            // Flags can arrive after mount, when afterMount already skipped the load.
            if (
                values.featureFlags[FEATURE_FLAGS.UPTIME_MONITORING] &&
                values.monitors === null &&
                !values.monitorsLoading
            ) {
                actions.loadMonitors()
            }
        },
        closeCreateModal: () => actions.resetNewMonitor(),
        submitNewMonitorSuccess: () => {
            actions.closeCreateModal()
            lemonToast.success('Monitor created')
        },
        setNewMonitorValue: ({ name }) => {
            // kea-forms clears a server error only on blur, which would block a retry with Enter.
            const field = String(Array.isArray(name) ? name[0] : name)
            if (field in values.newMonitorManualErrors) {
                const { [field]: _, ...rest } = values.newMonitorManualErrors
                actions.setNewMonitorManualErrors(rest)
            }
        },
        submitNewMonitorFailure: ({ error }) => {
            // Client-side validation also lands here, and the form already shows those errors on the fields.
            if (!(error instanceof ApiError)) {
                return
            }
            if (error.attr && error.attr in NEW_MONITOR_DEFAULTS) {
                actions.setNewMonitorManualErrors({ [error.attr]: error.detail })
            } else {
                lemonToast.error("Couldn't create the monitor. Try again.")
            }
        },
        deleteMonitorFailure: ({ errorObject }) => {
            // The global loader handler toasts errors that have a status, but not network failures.
            if (errorObject?.status === undefined) {
                lemonToast.error("Couldn't delete the monitor. Check your connection and try again.")
            }
        },
        confirmDeleteMonitor: ({ monitor }) => {
            LemonDialog.open({
                title: `Delete ${monitor.name}?`,
                description: 'This removes the monitor and its settings. You can create it again later.',
                primaryButton: {
                    children: 'Delete',
                    status: 'danger',
                    onClick: () => actions.deleteMonitor(monitor),
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
    })),

    afterMount(({ actions, values }) => {
        // The scene mounts this logic before it checks the flag, and the API 404s while the flag is off.
        if (values.featureFlags[FEATURE_FLAGS.UPTIME_MONITORING]) {
            actions.loadMonitors()
        }
    }),
])
