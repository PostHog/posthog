export type replayCommentsLogicType = MakeLogicType<replayCommentsLogicValues, replayCommentsLogicActions, Record<string, any>, replayCommentsLogicMeta>;

export const replayCommentsLogic = kea<replayCommentsLogicType>([
    path(() => ['products', 'replay', 'comments', 'replayCommentsLogic']),
    connect(() => ({
        values: [userLogic, ['user']],
    })),
    actions({
        loadReplayComments: true,
        loadMoreReplayComments: true,
    }),
    loaders(({ values }) => ({
        commentPage: [
            null as ReplayCommentPage | null,
            {
                loadReplayComments: async (_, breakpoint): Promise<ReplayCommentPage | null> => {
                    const userId = values.user?.id
                    if (!userId) {
                        return null
                    }
                    const response = await commentsList(String(getCurrentTeamId()), {
                        scope: ActivityScope.REPLAY,
                        created_by: userId,
                    })
                    breakpoint()
                    return { comments: response.results, nextCursor: cursorFromNextUrl(response.next) }
                },
                loadMoreReplayComments: async (_, breakpoint): Promise<ReplayCommentPage | null> => {
                    const userId = values.user?.id
                    const cursor = values.commentPage?.nextCursor
                    if (!userId || !cursor) {
                        return values.commentPage
                    }
                    const response = await commentsList(String(getCurrentTeamId()), {
                        scope: ActivityScope.REPLAY,
                        created_by: userId,
                        cursor,
                    })
                    breakpoint()
                    return {
                        comments: [...(values.commentPage?.comments ?? []), ...response.results],
                        nextCursor: cursorFromNextUrl(response.next),
                    }
                },
            },
        ],
    })),
    reducers({
        hasLoadError: [
            false,
            {
                loadReplayComments: () => false,
                loadReplayCommentsSuccess: () => false,
                loadReplayCommentsFailure: () => true,
            },
        ],
    }),
    selectors(() => ({
        commentRows: [
            (s) => [s.commentPage],
            (commentPage: ReplayCommentPage | null): ReplayCommentRow[] =>
                (commentPage?.comments ?? []).map(toCommentRow),
        ],
        hasMoreComments: [
            (s) => [s.commentPage],
            (commentPage: ReplayCommentPage | null): boolean => !!commentPage?.nextCursor,
        ],
        // Keeps the empty state off the screen until the first page has answered
        firstPageLoading: [
            (s) => [s.commentPageLoading, s.commentPage],
            (commentPageLoading: boolean, commentPage: ReplayCommentPage | null): boolean =>
                commentPageLoading && commentPage === null,
        ],
    })),
    afterMount(({ actions }) => {
        actions.loadReplayComments()
    }),
])
