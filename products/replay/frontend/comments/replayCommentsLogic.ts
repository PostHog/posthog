import type { CommentApi } from 'products/platform_features/frontend/generated/api.schemas'

type ReplayCommentContext = {
    time_in_recording?: string
    milliseconds_into_recording?: number
}

export type ReplayCommentRow = {
    id: string
    text: string
    createdAt: string
    recordingUrl: string | null
    /** Position in the recording as `mm:ss`, or null for a comment with no player position. */
    timeInRecording: string | null
    isTask: boolean
    isCompleted: boolean
}

export type ReplayCommentPage = {
    comments: CommentApi[]
    nextCursor: string | null
}

/** The API returns the next page as a full URL; only its cursor is needed to ask for that page. */
function cursorFromNextUrl(nextUrl: string | null | undefined): string | null {
    if (!nextUrl) {
        return null
    }
    try {
        return new URL(nextUrl, window.location.origin).searchParams.get('cursor')
    } catch {
        return null
    }
}

function toCommentRow(comment: CommentApi): ReplayCommentRow {
    // The comment serializer types both fields as free-form JSON, so the replay shape is asserted here
    const itemContext = (comment.item_context ?? null) as ReplayCommentContext | null
    const richContent = (comment.rich_content ?? null) as JSONContent | null
    const millisecondsIntoRecording = itemContext?.milliseconds_into_recording

    return {
        id: comment.id,
        text: getCommentText({ content: comment.content, rich_content: richContent }),
        createdAt: comment.created_at,
        recordingUrl:
            getRecordingLinkInfo({
                scope: comment.scope ?? '',
                item_id: comment.item_id,
                item_context: itemContext,
            })?.url ?? null,
        timeInRecording:
            millisecondsIntoRecording === undefined
                ? null
                : colonDelimitedDuration(millisecondsIntoRecording / 1000, null),
        isTask: !!comment.is_task,
        isCompleted: !!comment.completed_at,
    }
}

