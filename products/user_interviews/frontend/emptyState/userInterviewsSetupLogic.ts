import { MakeLogicType, afterMount, connect, kea, listeners, path } from 'kea'
import { loaders } from 'kea-loaders'

import { productSetupStatusLogic } from 'lib/components/ProductEmptyState/productSetupStatusLogic'
import type { ProductSetupStatus } from 'lib/components/ProductEmptyState/types'
import { teamLogic } from 'scenes/teamLogic'

import { ProductKey } from '~/queries/schema/schema-general'

import { userInterviewTopicsList, userInterviewsList } from 'products/user_interviews/frontend/generated/api'

const POLL_INTERVAL_MS = 20000
// The poll exists to catch a topic created by PostHog AI while this screen is up. Roughly ten
// minutes of checks covers that; past it, a remount re-arms the poll. Without a cap, leaving
// the tab open issues a request every 20 seconds indefinitely, and a failing endpoint turns
// into an endless retry underneath a scene that already loads its own topics.
const POLL_MAX_TICKS = 30

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userInterviewsSetupLogicValues {
    setupStatus: ProductSetupStatus // productSetupStatusLogic
    currentProjectId: number | string // teamLogic
    topicCount: number | null
    topicCountLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userInterviewsSetupLogicActions {
    setDetectedStatus: (status: ProductSetupStatus) => {
        status: ProductSetupStatus
    } // productSetupStatusLogic
    loadTopicCount: (_: void) => void
    loadTopicCountFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTopicCountSuccess: (
        topicCount: number,
        payload?: void
    ) => {
        topicCount: number
        payload?: void
    }
}

export type userInterviewsSetupLogicType = MakeLogicType<
    userInterviewsSetupLogicValues,
    userInterviewsSetupLogicActions
>

/**
 * Setup detection for the user research empty state. User research is a
 * creation-first product, so "set up" simply means the project has at least one
 * research topic or interview response - no event or traffic signal involved.
 * Re-checks on every mount (the scene gate mounts it), which covers returning
 * after creating a topic.
 */
export const userInterviewsSetupLogic = kea<userInterviewsSetupLogicType>([
    path(['products', 'user_interviews', 'frontend', 'emptyState', 'userInterviewsSetupLogic']),
    connect(() => ({
        actions: [productSetupStatusLogic({ productKey: ProductKey.USER_INTERVIEWS }), ['setDetectedStatus']],
        values: [
            productSetupStatusLogic({ productKey: ProductKey.USER_INTERVIEWS }),
            ['status as setupStatus'],
            teamLogic,
            ['currentProjectId'],
        ],
    })),
    loaders(({ values }) => ({
        topicCount: [
            null as number | null,
            {
                loadTopicCount: async (_: void, breakpoint): Promise<number> => {
                    // Responses outlive their topic: deleting a topic nulls the link rather than
                    // cascading, and audio uploads never get one. Counting topics alone would hide
                    // a project's responses behind the setup screen, and the scene's search box is
                    // the only place to reach them.
                    const [topics, interviews] = await Promise.all([
                        userInterviewTopicsList(String(values.currentProjectId), { limit: 1 }),
                        userInterviewsList(String(values.currentProjectId), { limit: 1 }),
                    ])
                    breakpoint()
                    return topics.count + interviews.count
                },
            },
        ],
    })),
    listeners(({ actions, cache, values }) => ({
        loadTopicCountSuccess: () => {
            const hasData = (values.topicCount ?? 0) > 0
            if (hasData) {
                cache.disposables.dispose('poll')
            }
            actions.setDetectedStatus(hasData ? 'has-data' : 'needs-setup')
        },
        loadTopicCountFailure: () => {
            // Never strand the gate on its spinner: if nothing has answered yet, fail
            // open to the real scene. Don't downgrade an existing answer on a blip.
            if (values.setupStatus === 'loading') {
                actions.setDetectedStatus('unknown')
            }
            // The scene loads its own topics, so retrying a broken endpoint here buys nothing.
            cache.disposables.dispose('poll')
        },
    })),
    afterMount(({ actions, cache }) => {
        actions.loadTopicCount()
        // Topics are created by PostHog AI in the side panel while the gate stays on
        // screen, so poll until one lands rather than waiting for a remount.
        cache.disposables.add(() => {
            let ticks = 0
            const interval = setInterval(() => {
                ticks += 1
                if (ticks > POLL_MAX_TICKS) {
                    cache.disposables.dispose('poll')
                    return
                }
                actions.loadTopicCount()
            }, POLL_INTERVAL_MS)
            return () => clearInterval(interval)
        }, 'poll')
    }),
])
