export const featureFlagRequestUsageLogic = kea<featureFlagRequestUsageLogicType>([
    path(['products', 'featureFlags', 'requestUsage', 'featureFlagRequestUsageLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        setInterval: (interval: FeatureFlagRequestUsageInterval) => ({ interval }),
        setDates: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setMetric: (metric: FeatureFlagRequestUsageMetric) => ({ metric }),
        setRequestType: (requestType: FeatureFlagRequestTypeFilter) => ({ requestType }),
        setSelectedSDKs: (selectedSDKs: string[]) => ({ selectedSDKs }),
        downloadCsv: true,
    }),
    loaders(({ values }) => ({
        usageResponse: [
            null as FeatureFlagRequestUsageResponseApi | null,
            {
                loadUsageResponse: async (_: void, breakpoint) => {
                    if (!values.currentProjectId) {
                        throw new Error('No project selected')
                    }
                    const range = resolveDateRange(values.dateFrom, values.dateTo)
                    const params = {
                        date_from: range.dateFrom.toISOString(),
                        date_to: range.dateTo.toISOString(),
                        time_interval: values.interval,
                    }
                    const response = await api.featureFlagRequestUsageList(String(values.currentProjectId), params)
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers({
        interval: ['day' as FeatureFlagRequestUsageInterval, { setInterval: (_, { interval }) => interval }],
        dateFrom: ['-30d', { setDates: (_, { dateFrom }) => dateFrom ?? '-30d' }],
        dateTo: [null as string | null, { setDates: (_, { dateTo }) => dateTo }],
        metric: ['requests' as FeatureFlagRequestUsageMetric, { setMetric: (_, { metric }) => metric }],
        requestType: ['all' as FeatureFlagRequestTypeFilter, { setRequestType: (_, { requestType }) => requestType }],
        selectedSDKs: [[] as string[], { setSelectedSDKs: (_, { selectedSDKs }) => selectedSDKs }],
        loadError: [
            false,
            {
                loadUsageResponse: () => false,
                loadUsageResponseSuccess: () => false,
                loadUsageResponseFailure: () => true,
            },
        ],
    }),
    selectors({
        isHourlyAvailable: [
            (s) => [s.dateFrom, s.dateTo],
            (dateFrom: string, dateTo: string | null): boolean => {
                const range = resolveDateRange(dateFrom, dateTo)
                return range.dateTo.diff(range.dateFrom, 'day', true) <= MAX_HOURLY_RANGE_DAYS
            },
        ],
        sdkOptions: [
            (s) => [s.usageResponse],
            (response: FeatureFlagRequestUsageResponseApi | null): { key: string; label: string }[] =>
                Array.from(new Set(response?.results.map(({ sdk }) => sdk) ?? []))
                    .sort()
                    .map((sdk) => ({ key: sdk, label: sdk })),
        ],
        filteredItems: [
            (s) => [s.usageResponse, s.selectedSDKs, s.requestType],
            (
                response: FeatureFlagRequestUsageResponseApi | null,
                selectedSDKs: string[],
                requestType: FeatureFlagRequestTypeFilter
            ): FeatureFlagRequestUsageItemApi[] => filterItems(response, selectedSDKs, requestType),
        ],
        dates: [
            (s) => [s.dateFrom, s.dateTo, s.interval],
            (dateFrom: string, dateTo: string | null, interval: FeatureFlagRequestUsageInterval): string[] =>
                buildDates(dateFrom, dateTo, interval),
        ],
        series: [
            (s) => [s.filteredItems, s.dates, s.metric, s.interval],
            (
                items: FeatureFlagRequestUsageItemApi[],
                dates: string[],
                metric: FeatureFlagRequestUsageMetric,
                interval: FeatureFlagRequestUsageInterval
            ): FeatureFlagRequestUsageSeries[] => {
                const seriesByLabel = new Map<string, Map<string, number>>()
                for (const item of items) {
                    const evaluationLabel = item.request_type === 'remote_evaluation' ? 'remote' : 'local'
                    const label = `${item.sdk} (${evaluationLabel})`
                    const values = seriesByLabel.get(label) ?? new Map<string, number>()
                    const value = metric === 'requests' ? item.request_count : item.billing_units
                    const bucket = dayjs(item.bucket).utc().startOf(interval).toISOString()
                    values.set(bucket, (values.get(bucket) ?? 0) + value)
                    seriesByLabel.set(label, values)
                }
                return Array.from(seriesByLabel.entries()).map(([label, values]) => ({
                    id: stableSeriesId(label),
                    label,
                    dates,
                    data: dates.map((date) => values.get(date) ?? 0),
                }))
            },
        ],
        sdkTotals: [
            (s) => [s.filteredItems],
            (items: FeatureFlagRequestUsageItemApi[]): FeatureFlagRequestUsageSdkTotal[] => {
                const totals = new Map<string, FeatureFlagRequestUsageSdkTotal>()
                for (const item of items) {
                    const current = totals.get(item.sdk) ?? {
                        sdk: item.sdk,
                        remoteRequests: 0,
                        localRequests: 0,
                        billingUnits: 0,
                        billingUnitsShare: 0,
                    }
                    if (item.request_type === 'remote_evaluation') {
                        current.remoteRequests += item.request_count
                    } else {
                        current.localRequests += item.request_count
                    }
                    current.billingUnits += item.billing_units
                    totals.set(item.sdk, current)
                }
                const totalBillingUnits = Array.from(totals.values()).reduce((sum, item) => sum + item.billingUnits, 0)
                for (const item of totals.values()) {
                    item.billingUnitsShare = totalBillingUnits === 0 ? 0 : (item.billingUnits / totalBillingUnits) * 100
                }
                return Array.from(totals.values()).sort((a, b) => b.billingUnits - a.billingUnits)
            },
        ],
        totalRemoteRequests: [
            (s) => [s.filteredItems],
            (items: FeatureFlagRequestUsageItemApi[]): number =>
                items.reduce(
                    (total, item) => total + (item.request_type === 'remote_evaluation' ? item.request_count : 0),
                    0
                ),
        ],
        totalLocalRequests: [
            (s) => [s.filteredItems],
            (items: FeatureFlagRequestUsageItemApi[]): number =>
                items.reduce(
                    (total, item) => total + (item.request_type === 'local_evaluation' ? item.request_count : 0),
                    0
                ),
        ],
        totalBillingUnits: [
            (s) => [s.filteredItems],
            (items: FeatureFlagRequestUsageItemApi[]): number =>
                items.reduce((total, item) => total + item.billing_units, 0),
        ],
        largestSdk: [
            (s) => [s.sdkTotals],
            (sdkTotals: FeatureFlagRequestUsageSdkTotal[]): FeatureFlagRequestUsageSdkTotal | null =>
                sdkTotals[0] ?? null,
        ],
    }),
    listeners(({ actions, values }) => ({
        setInterval: () => actions.loadUsageResponse(),
        setDates: ({ dateFrom, dateTo }) => {
            const range = resolveDateRange(dateFrom ?? '-30d', dateTo)
            if (range.dateTo.diff(range.dateFrom, 'day', true) > MAX_HOURLY_RANGE_DAYS) {
                actions.setInterval('day')
            } else {
                actions.loadUsageResponse()
            }
        },
        downloadCsv: () => {
            const header = ['bucket', 'sdk', 'request_type', 'request_count', 'billing_units']
            const rows = values.filteredItems.map((item) => [
                item.bucket,
                item.sdk,
                item.request_type,
                item.request_count,
                item.billing_units,
            ])
            const csv = [header, ...rows].map((row) => row.map(csvCell).join(',')).join('\n')
            downloadBlob(new Blob([csv], { type: 'text/csv;charset=utf-8' }), `feature-flag-request-usage.csv`)
        },
    })),
    afterMount(({ actions }) => actions.loadUsageResponse()),
])
