import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers } from 'kea'
import posthog from 'posthog-js'

import { isApprovalRequiredError } from 'lib/api-error'
import { handleApprovalRequired } from 'lib/approvals/utils'
import { activityLogLogic } from 'lib/components/ActivityLog/activityLogLogic'
import { LemonDialog } from 'lib/lemon-ui/LemonDialog'
import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { featureFlagLogic } from 'scenes/feature-flags/featureFlagLogic'
import { projectLogic } from 'scenes/projectLogic'

import { ActivityScope, FeatureFlagType } from '~/types'

import { featureFlagsVersionsRestoreCreate, featureFlagsVersionsRetrieve } from '../generated/api'
import type { FeatureFlagVersionResponseApi } from '../generated/api.schemas'
import { FeatureFlagRestoreVersionPreview } from './FeatureFlagRestoreVersionPreview'

export interface FeatureFlagRestoreVersionLogicProps {
    flagId: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagRestoreVersionLogicValues {
    featureFlag: FeatureFlagType // featureFlagLogic
    currentProjectId: number | null // projectLogic
    busyVersion: number | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagRestoreVersionLogicActions {
    loadFeatureFlag: () => any // featureFlagLogic
    confirmRestoreVersion: (
        version: number,
        currentVersion: number
    ) => {
        currentVersion: number
        version: number
    }
    restoreVersion: (version: number) => {
        version: number
    }
    setBusyVersion: (version: number | null) => {
        version: number | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagRestoreVersionLogicMeta {
    key: number
}

export type featureFlagRestoreVersionLogicType = MakeLogicType<
    featureFlagRestoreVersionLogicValues,
    featureFlagRestoreVersionLogicActions,
    FeatureFlagRestoreVersionLogicProps,
    featureFlagRestoreVersionLogicMeta
>

export const featureFlagRestoreVersionLogic = kea<featureFlagRestoreVersionLogicType>([
    props({} as FeatureFlagRestoreVersionLogicProps),
    key((props) => props.flagId),
    path((key) => ['products', 'feature_flags', 'frontend', 'restoreVersion', 'featureFlagRestoreVersionLogic', key]),
    connect((props: FeatureFlagRestoreVersionLogicProps) => ({
        values: [projectLogic, ['currentProjectId'], featureFlagLogic({ id: props.flagId }), ['featureFlag']],
        actions: [featureFlagLogic({ id: props.flagId }), ['loadFeatureFlag']],
    })),
    actions({
        restoreVersion: (version: number) => ({ version }),
        confirmRestoreVersion: (version: number, currentVersion: number) => ({ version, currentVersion }),
        setBusyVersion: (version: number | null) => ({ version }),
    }),
    reducers({
        busyVersion: [
            null as number | null,
            {
                setBusyVersion: (_, { version }) => version,
            },
        ],
    }),
    listeners((logic) => ({
        restoreVersion: async ({ version }) => {
            const { actions, values, props } = logic
            if (values.busyVersion !== null) {
                return
            }
            actions.setBusyVersion(version)
            // The version the preview is computed against. The restore sends it, so a change that
            // lands while the dialog is open is refused instead of being overwritten.
            const currentVersion = values.featureFlag.version ?? 0
            let target: FeatureFlagVersionResponseApi
            try {
                target = await featureFlagsVersionsRetrieve(String(values.currentProjectId), props.flagId, version)
            } catch (error: any) {
                if (featureFlagRestoreVersionLogic.isMounted(props)) {
                    actions.setBusyVersion(null)
                    lemonToast.error(error?.detail || `Couldn't load version ${version}. Try again in a moment.`)
                }
                return
            }
            // The person left the flag while the version loaded, so there is no page to preview it on.
            if (!featureFlagRestoreVersionLogic.isMounted(props)) {
                return
            }
            actions.setBusyVersion(null)
            posthog.capture('feature flag version restore opened', {
                feature_flag_id: props.flagId,
                restored_version: version,
                versions_back: currentVersion - version,
            })
            LemonDialog.open({
                title: `Restore version ${version}?`,
                width: '40rem',
                content: <FeatureFlagRestoreVersionPreview flag={values.featureFlag} target={target} />,
                primaryButton: {
                    children: 'Restore this version',
                    'data-attr': 'feature-flag-restore-version-confirm',
                    onClick: () => actions.confirmRestoreVersion(version, currentVersion),
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        confirmRestoreVersion: async ({ version, currentVersion }) => {
            const { actions, values, props } = logic
            if (values.busyVersion !== null) {
                return
            }
            actions.setBusyVersion(version)
            try {
                await featureFlagsVersionsRestoreCreate(String(values.currentProjectId), props.flagId, version, {
                    version: currentVersion,
                })
                lemonToast.success(`Restored version ${version}`)
                posthog.capture('feature flag version restored', {
                    feature_flag_id: props.flagId,
                    restored_version: version,
                    versions_back: currentVersion - version,
                })
            } catch (error: any) {
                // Both are 409s, so the approval check has to come first.
                if (isApprovalRequiredError(error)) {
                    handleApprovalRequired(error, 'feature_flag', props.flagId)
                } else if (error?.status === 409) {
                    lemonToast.error(
                        'This flag changed while you were reviewing the restore. Review the history and try again.'
                    )
                } else {
                    lemonToast.error(error?.detail || `Couldn't restore version ${version}. Try again in a moment.`)
                }
            }
            activityLogLogic
                .findMounted({ scope: ActivityScope.FEATURE_FLAG, id: props.flagId })
                ?.actions.fetchActivity()
            if (featureFlagRestoreVersionLogic.isMounted(props)) {
                actions.setBusyVersion(null)
                actions.loadFeatureFlag()
            }
        },
    })),
])
