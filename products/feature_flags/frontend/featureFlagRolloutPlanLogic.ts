export type featureFlagRolloutPlanLogicType = MakeLogicType<
    featureFlagRolloutPlanLogicValues,
    featureFlagRolloutPlanLogicActions,
    FeatureFlagRolloutPlanLogicProps,
    featureFlagRolloutPlanLogicMeta
>

export const featureFlagRolloutPlanLogic = kea<featureFlagRolloutPlanLogicType>([
    path((key) => ['products', 'feature_flags', 'frontend', 'featureFlagRolloutPlanLogic', key]),
    props({} as FeatureFlagRolloutPlanLogicProps),
    key((props) => props.id),

    connect(() => ({
        values: [
            maxGlobalLogic,
            ['isMaxAvailable', 'effectivePhaiView', 'dataProcessingAccepted'],
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['seed'],
        ],
        actions: [
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setSeed', 'consumeSeed'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['clearActiveCreation', 'setHistoryExpanded'],
            sidePanelStateLogic,
            ['openSidePanel'],
        ],
    })),

    actions({
        startPlan: (flagKey: string, projectId: number | null) => ({ flagKey, projectId }),
        copyAgentPrompt: (flagKey: string, projectId: number | null) => ({ flagKey, projectId }),
        markPlanStarted: true,
        resetPlanStarted: true,
    }),

    reducers({
        planStarted: [
            false,
            {
                markPlanStarted: () => true,
                resetPlanStarted: () => false,
            },
        ],
    }),

    selectors({
        isAiPlanAvailable: [
            (s) => [s.isMaxAvailable, s.effectivePhaiView],
            (isMaxAvailable: boolean, effectivePhaiView: PhaiViewMode): boolean =>
                isMaxAvailable && effectivePhaiView === 'new',
        ],
    }),

    listeners(({ actions, values, cache, props }) => {
        const cancelPlan = (): void => {
            if (!values.planStarted) {
                return
            }
            if (values.seed && values.seed === cache.pendingSeed) {
                actions.consumeSeed()
            }
            actions.resetPlanStarted()
        }

        return {
            startPlan: ({ flagKey, projectId }) => {
                if (values.planStarted || !values.isAiPlanAvailable) {
                    return
                }
                actions.markPlanStarted()
                actions.clearActiveCreation()
                actions.setHistoryExpanded(false)
                cache.pendingSeed = {
                    prompt: FEATURE_FLAG_ROLLOUT_PLAN_PROMPT,
                    autoSubmit: values.dataProcessingAccepted,
                    contextItems: featureFlagRolloutPlanContextItems({ id: props.id, key: flagKey }, projectId),
                }
                actions.setSeed(cache.pendingSeed)
                actions.openSidePanel(SidePanelTab.Max)
                posthog.capture('feature flag rollout hint plan clicked', { flag_id: props.id, flag_key: flagKey })
            },
            copyAgentPrompt: async ({ flagKey, projectId }) => {
                const copied = await copyToClipboard(featureFlagRolloutAgentPrompt(flagKey, projectId), 'prompt')
                if (copied) {
                    posthog.capture('feature flag rollout hint prompt copied', { flag_id: props.id, flag_key: flagKey })
                }
            },
            [sidePanelStateLogic.actionTypes.setSidePanelOpen]: ({ open }) => {
                if (!open) {
                    cancelPlan()
                }
            },
            [sidePanelStateLogic.actionTypes.openSidePanel]: ({ tab }) => {
                if (tab !== SidePanelTab.Max) {
                    cancelPlan()
                }
            },
        }
    }),

    afterMount(({ props }) => {
        posthog.capture('feature flag rollout hint shown', { flag_id: props.id })
    }),

    beforeUnmount(({ actions, values, cache }) => {
        if (values.seed && values.seed === cache.pendingSeed) {
            actions.consumeSeed()
        }
    }),
])
