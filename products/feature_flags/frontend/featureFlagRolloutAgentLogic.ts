export const featureFlagRolloutAgentLogic = kea<featureFlagRolloutAgentLogicType>([
    props({} as FeatureFlagRolloutAgentLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'feature_flags', 'frontend', 'featureFlagRolloutAgentLogic', key]),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], teamLogic, ['currentProjectId']],
    })),
    actions({
        openSetupModal: true,
        closeSetupModal: true,
    }),
    loaders(({ props, values }) => ({
        plans: [
            [] as FeatureFlagRolloutPlanApi[],
            {
                loadPlans: async () =>
                    await api.featureFlagRolloutPlansList(String(values.currentProjectId), {
                        feature_flag: props.id,
                    }),
                stopPlan: async (planId: string) => {
                    const stopped = await api.featureFlagRolloutPlansStopCreate(
                        String(values.currentProjectId),
                        planId,
                        { reason: 'Stopped from the feature flag page.' }
                    )
                    return values.plans.map((plan) => (plan.id === planId ? stopped : plan))
                },
            },
        ],
    })),
    forms(({ actions, props, values }) => ({
        setup: {
            defaults: DEFAULT_SETUP,
            errors: ({ percentages, soakHours, healthChecks }) => ({
                percentages: parseRolloutPercentages(percentages)
                    ? undefined
                    : 'Enter whole numbers from 1 to 100 in increasing order, such as 5, 25, 50, 100.',
                soakHours: soakHours >= 1 ? undefined : 'Wait at least 1 hour between steps.',
                healthChecks: healthChecks.trim() ? undefined : 'Say what the agent should check.',
            }),
            submit: async ({ conditionIndex, percentages, soakHours, healthChecks }, breakpoint) => {
                try {
                    const plan = await api.featureFlagRolloutPlansCreate(String(values.currentProjectId), {
                        feature_flag: props.id,
                        condition_index: conditionIndex,
                        percentages: parseRolloutPercentages(percentages) ?? [],
                        soak_hours: soakHours,
                        health_checks: healthChecks,
                    })
                    breakpoint()
                    actions.loadPlansSuccess([plan, ...values.plans])
                    actions.closeSetupModal()
                    actions.resetSetup()
                } catch (error: any) {
                    lemonToast.error(error.detail || 'Could not start the rollout. Try again.')
                    throw error
                }
            },
        },
    })),
    reducers({
        isSetupModalOpen: [
            false,
            {
                openSetupModal: () => true,
                closeSetupModal: () => false,
            },
        ],
    }),
    selectors({
        isAgentRolloutAvailable: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.FEATURE_FLAG_ROLLOUT_AGENT],
        ],
        latestPlan: [
            (s) => [s.plans],
            (plans: FeatureFlagRolloutPlanApi[]): FeatureFlagRolloutPlanApi | null => plans[0] ?? null,
        ],
        activePlan: [
            (s) => [s.latestPlan],
            (latestPlan: FeatureFlagRolloutPlanApi | null): FeatureFlagRolloutPlanApi | null =>
                latestPlan?.status === 'active' ? latestPlan : null,
        ],
    }),
    listeners(({ props }) => ({
        openSetupModal: () => {
            posthog.capture('feature flag rollout agent setup opened', { flag_id: props.id })
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.isAgentRolloutAvailable) {
            actions.loadPlans()
        }
    }),
])
