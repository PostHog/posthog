export function parseRolloutPercentages(text: string): number[] | null {
    const parts = text.split(',').map((part) => part.trim())
    const percentages = parts.map(Number)
    const valid = percentages.every(
        (percentage, index) =>
            parts[index] !== '' &&
            Number.isInteger(percentage) &&
            percentage >= 1 &&
            percentage <= 100 &&
            (index === 0 || percentage > percentages[index - 1])
    )
    return valid ? percentages : null
}

