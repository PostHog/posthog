/**
 * Drives the flag page's "Review cleanup with AI" action: opens the PostHog AI side panel on a fresh
 * conversation, seeded with a request to assess this flag, carrying the cleanup skill and the flag's
 * saved identity as context scoped to that one action (see featureFlagAiContext.ts).
 *
 * Context registration happens here as a plain kea dispatch, not through a React `useAttachedContext`
 * effect, so it lands in the store before `taskTrackerSceneLogic` reads it at send time.
 */
export const featureFlagCleanupAssessmentLogic = kea<featureFlagCleanupAssessmentLogicType>([
    path((key) => ['products', 'feature_flags', 'frontend', 'featureFlagCleanupAssessmentLogic', key]),
    props({} as FeatureFlagCleanupAssessmentLogicProps),
    key((props) => props.id),

    connect(() => ({
        values: [
            maxGlobalLogic,
            ['isMaxAvailable', 'effectivePhaiView'],
            enabledFeaturesLogic,
            ['featureFlags'],
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['seed'],
        ],
        actions: [
            attachedContextLogic,
            ['registerContext', 'deregisterContext', 'undismissContext', 'markContextSent'],
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setSeed', 'consumeSeed'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['clearActiveCreation', 'setHistoryExpanded'],
            sidePanelStateLogic,
            ['openSidePanel'],
        ],
    })),

    actions({
        startAssessment: (featureFlag: FeatureFlagType & { id: number }, projectId: number | null) => ({
            featureFlag,
            projectId,
        }),
        markAssessmentStarted: true,
    }),

    reducers({
        assessmentStarted: [
            false,
            {
                markAssessmentStarted: () => true,
            },
        ],
    }),

    selectors({
        // Scoped to the new sandbox view: legacy Max chat does not run in the agent sandbox, so the
        // cleanup skill bundled into that image is not present there.
        isCleanupAvailable: [
            (s) => [s.isMaxAvailable, s.effectivePhaiView, s.featureFlags],
            (isMaxAvailable: boolean, effectivePhaiView: PhaiViewMode, featureFlags: FeatureFlagsSet): boolean =>
                isMaxAvailable &&
                effectivePhaiView === 'new' &&
                !!featureFlags[FEATURE_FLAGS.FEATURE_FLAG_CLEANUP_ASSESSMENT],
        ],
    }),

    listeners(({ actions, values, cache, props }) => ({
        startAssessment: ({ featureFlag, projectId }) => {
            if (values.assessmentStarted || !values.isCleanupAvailable) {
                return
            }
            actions.markAssessmentStarted()
            // A dismissal is global and has no expiry, so a chip closed in an earlier conversation would
            // otherwise silently strip this request's skill and its assessment-only instruction.
            actions.undismissContext(
                attachedContextItemKey(FEATURE_FLAG_CLEANUP_SKILL_CHIP_CONTEXT_ITEM),
                FEATURE_FLAG_CLEANUP_DISMISS_GROUP
            )
            const items = featureFlagCleanupAssessmentContextItems(featureFlag, projectId)
            const target = items.find((item) => item.type === 'feature_flag_cleanup_target')
            cache.targetKey = target ? attachedContextItemKey(target) : null
            actions.registerContext(providerId(featureFlag.id), items)
            // Do not resume whatever the panel was already showing - a run in progress, history, or an
            // unrelated draft - so this action never appends to an unrelated task.
            actions.clearActiveCreation()
            actions.setHistoryExpanded(false)
            cache.pendingSeed = { prompt: FEATURE_FLAG_CLEANUP_ASSESSMENT_PROMPT, autoSubmit: true }
            actions.setSeed(cache.pendingSeed)
            actions.openSidePanel(SidePanelTab.Max)
            posthog.capture('feature flag stale banner review cleanup with ai clicked', {
                flag_id: featureFlag.id,
                flag_key: featureFlag.key,
            })
        },
        // Release the context once a sent message carries it, so a later conversation on this page does not
        // get the assessment-only instruction. A failed send marks nothing, so a retry still carries it.
        markContextSent: ({ keys }) => {
            if (cache.targetKey && keys.includes(cache.targetKey)) {
                actions.deregisterContext(providerId(props.id))
            }
        },
    })),

    // The registration is a global, app-wide store keyed by provider id (see attachedContextLogic), so
    // leaving it behind here would keep attaching the cleanup skill and this flag's identity to every
    // conversation started anywhere in the app after the user has navigated away from this flag.
    beforeUnmount(({ actions, props, values, cache }) => {
        actions.deregisterContext(providerId(props.id))
        // The runner reads the attached context only when it consumes the seed, and it can mount after this
        // logic unmounts (its chunks load lazily). A seed left pending here would auto-submit without the
        // target, the skill and the assessment-only instruction. The identity check leaves alone a seed that
        // another producer set after this one.
        if (values.seed && values.seed === cache.pendingSeed) {
            actions.consumeSeed()
        }
    }),
])
