export type featureFlagCleanupAssessmentLogicType = MakeLogicType<
    featureFlagCleanupAssessmentLogicValues,
    featureFlagCleanupAssessmentLogicActions,
    FeatureFlagCleanupAssessmentLogicProps,
    featureFlagCleanupAssessmentLogicMeta
>

export const featureFlagCleanupAssessmentLogic = kea<featureFlagCleanupAssessmentLogicType>([
    path((key) => ['products', 'feature_flags', 'frontend', 'featureFlagCleanupAssessmentLogic', key]),
    props({} as FeatureFlagCleanupAssessmentLogicProps),
    key((props) => props.id),

    connect(() => ({
        values: [
            maxGlobalLogic,
            ['isMaxAvailable', 'effectivePhaiView', 'dataProcessingAccepted'],
            enabledFeaturesLogic,
            ['featureFlags'],
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['seed'],
        ],
        actions: [
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setSeed', 'consumeSeed'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['clearActiveCreation', 'setHistoryExpanded'],
            sidePanelStateLogic,
            ['openSidePanel'],
        ],
    })),

    actions({
        startAssessment: (flagKey: string, projectId: number | null) => ({ flagKey, projectId }),
        markAssessmentStarted: true,
        resetAssessmentStarted: true,
    }),

    reducers({
        assessmentStarted: [
            false,
            {
                markAssessmentStarted: () => true,
                resetAssessmentStarted: () => false,
            },
        ],
    }),

    selectors({
        // Scoped to the new sandbox view: legacy Max chat does not run in the agent sandbox, so the
        // cleanup skill bundled into that image is not present there.
        isCleanupAvailable: [
            (s) => [s.isMaxAvailable, s.effectivePhaiView, s.featureFlags],
            (isMaxAvailable: boolean, effectivePhaiView: PhaiViewMode, featureFlags: FeatureFlagsSet): boolean =>
                isMaxAvailable &&
                effectivePhaiView === 'new' &&
                !!featureFlags[FEATURE_FLAGS.FEATURE_FLAG_CLEANUP_ASSESSMENT],
        ],
    }),

    listeners(({ actions, values, cache, props }) => {
        const cancelAssessment = (): void => {
            if (!values.assessmentStarted) {
                return
            }
            if (values.seed && values.seed === cache.pendingSeed) {
                actions.consumeSeed()
            }
            actions.resetAssessmentStarted()
        }

        return {
            startAssessment: ({ flagKey, projectId }) => {
                if (values.assessmentStarted || !values.isCleanupAvailable) {
                    return
                }
                actions.markAssessmentStarted()
                const contextItems = featureFlagCleanupAssessmentContextItems({ id: props.id, key: flagKey }, projectId)
                // Do not resume whatever the panel was already showing - a run in progress, history, or an
                // unrelated draft - so this action never appends to an unrelated task.
                actions.clearActiveCreation()
                actions.setHistoryExpanded(false)
                cache.pendingSeed = {
                    prompt: FEATURE_FLAG_CLEANUP_ASSESSMENT_PROMPT,
                    autoSubmit: values.dataProcessingAccepted,
                    contextItems,
                }
                actions.setSeed(cache.pendingSeed)
                actions.openSidePanel(SidePanelTab.Max)
                posthog.capture('feature flag stale banner review cleanup with ai clicked', {
                    flag_id: props.id,
                    flag_key: flagKey,
                })
            },
            [sidePanelStateLogic.actionTypes.setSidePanelOpen]: ({ open }) => {
                if (!open) {
                    cancelAssessment()
                }
            },
            [sidePanelStateLogic.actionTypes.openSidePanel]: ({ tab }) => {
                if (tab !== SidePanelTab.Max) {
                    cancelAssessment()
                }
            },
        }
    }),

    beforeUnmount(({ actions, values, cache }) => {
        // The runner can mount after this logic unmounts because its chunk loads lazily.
        if (values.seed && values.seed === cache.pendingSeed) {
            actions.consumeSeed()
        }
    }),
])
