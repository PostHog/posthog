import { MakeLogicType, afterMount, connect, kea, key, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { RetainedValues } from 'lib/utils/retainedValues'
import { projectLogic } from 'scenes/projectLogic'

import { FeatureFlagConfig, MultivariateFlagVariant } from '~/types'

import { isV1FeatureFlagConfig } from './featureFlagConfigFormat'
import { featureFlagsList } from './generated/api'
import type { FeatureFlagApi } from './generated/api.schemas'

const FLAG_LOOKUP_TTL_MS = 60 * 1000

const retainedFlagLookups = new RetainedValues<{ flag: FeatureFlagApi | null }>({
    maxEntries: 200,
    ttlMs: FLAG_LOOKUP_TTL_MS,
})

export interface FeatureFlagFilterSummaryLogicProps {
    flagKey: string
}

export interface FeatureFlagFilterSummary {
    active: boolean
    variants: MultivariateFlagVariant[] | null
    conditionCount: number | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagFilterSummaryLogicValues {
    currentProjectId: number | null // projectLogic
    flag: FeatureFlagApi | null
    flagLoading: boolean
    summary: FeatureFlagFilterSummary | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagFilterSummaryLogicActions {
    loadFlag: () => any
    loadFlagFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFlagSuccess: (
        flag: FeatureFlagApi | null,
        payload?: any
    ) => {
        flag: FeatureFlagApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagFilterSummaryLogicMeta {
    key: string
}

export type featureFlagFilterSummaryLogicType = MakeLogicType<
    featureFlagFilterSummaryLogicValues,
    featureFlagFilterSummaryLogicActions,
    FeatureFlagFilterSummaryLogicProps,
    featureFlagFilterSummaryLogicMeta
>

/** A short overview of the flag behind a `$feature/<key>` property filter, for its tooltip. */
export const featureFlagFilterSummaryLogic = kea<featureFlagFilterSummaryLogicType>([
    props({} as FeatureFlagFilterSummaryLogicProps),
    key((props) => props.flagKey),
    path((key) => ['products', 'feature_flags', 'frontend', 'featureFlagFilterSummaryLogic', key]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    loaders(({ props, values }) => ({
        flag: [
            null as FeatureFlagApi | null,
            {
                loadFlag: async () => {
                    if (!values.currentProjectId) {
                        return null
                    }
                    const response = await featureFlagsList(String(values.currentProjectId), { key: props.flagKey })
                    // The API matches the key case-insensitively, but flag keys that differ only by case can both exist.
                    const flag = response.results.find((flag) => flag.key === props.flagKey) ?? null
                    retainedFlagLookups.set(props.flagKey, { flag })
                    return flag
                },
            },
        ],
    })),
    selectors({
        summary: [
            (s) => [s.flag],
            (flag): FeatureFlagFilterSummary | null => {
                if (!flag) {
                    return null
                }
                const filters = flag.filters as FeatureFlagConfig | undefined
                const isV1 = !!filters && isV1FeatureFlagConfig(filters)
                return {
                    active: !!flag.active,
                    variants: isV1 ? (filters.multivariate?.variants ?? []) : null,
                    conditionCount: isV1 ? (filters.groups?.length ?? 0) : null,
                }
            },
        ],
    }),
    afterMount(({ actions, props }) => {
        const retained = retainedFlagLookups.get(props.flagKey)
        if (retained) {
            actions.loadFlagSuccess(retained.flag)
        } else {
            actions.loadFlag()
        }
    }),
])
