export interface rulesV2MatchCountLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        properties: (arg: any) => AnyPropertyFilter[]
        countable: (properties: AnyPropertyFilter[]) => boolean
    }
}

export type rulesV2MatchCountLogicType = MakeLogicType<
    rulesV2MatchCountLogicValues,
    rulesV2MatchCountLogicActions,
    RulesV2MatchCountLogicProps,
    rulesV2MatchCountLogicMeta
>

/**
 * How many persons or groups a rule's targeting matches, from the estimate the v1 release conditions show. An estimate is a
 * hint, so a failure shows inline with a retry instead of a toast.
 */
export const rulesV2MatchCountLogic = kea<rulesV2MatchCountLogicType>([
    props({} as RulesV2MatchCountLogicProps),
    key(({ propertiesKey, groupTypeIndex }) => `${groupTypeIndex ?? 'persons'}:${propertiesKey}`),
    path((key) => ['products', 'feature_flags', 'frontend', 'rulesV2MatchCountLogic', key]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        loadMatchCount: true,
        loadMatchCountSuccess: (matchCount: RulesV2MatchCount) => ({ matchCount }),
        loadMatchCountFailure: (error: BlastRadiusError) => ({ error }),
    }),
    reducers({
        matchCount: [
            null as RulesV2MatchCount | null,
            {
                loadMatchCount: () => null,
                loadMatchCountSuccess: (_, { matchCount }) => matchCount,
            },
        ],
        matchCountError: [
            null as BlastRadiusError | null,
            {
                loadMatchCount: () => null,
                loadMatchCountFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        properties: [
            () => [(_, props) => props.propertiesKey],
            (propertiesKey: string): AnyPropertyFilter[] => JSON.parse(propertiesKey),
        ],
        countable: [
            (s) => [s.properties],
            (properties: AnyPropertyFilter[]): boolean => !properties.some(isIncompleteRulesV2Condition),
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadMatchCount: async (_, breakpoint) => {
            let matchCount: RulesV2MatchCount
            try {
                matchCount = await sharedMatchCount(values.currentProjectId, props, values.properties)
            } catch (error) {
                breakpoint()
                actions.loadMatchCountFailure(toBlastRadiusError(error))
                return
            }
            breakpoint()
            actions.loadMatchCountSuccess(matchCount)
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.countable) {
            actions.loadMatchCount()
        }
    }),
])
