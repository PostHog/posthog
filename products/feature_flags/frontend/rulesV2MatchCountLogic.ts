export interface rulesV2MatchCountLogicValues {
    currentProjectId: number | null // projectLogic
    countable: boolean
    matchCount: RulesV2MatchCount | null
    matchCountError: BlastRadiusError | null
    properties: AnyPropertyFilter[]
}

