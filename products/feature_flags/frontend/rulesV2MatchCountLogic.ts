import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'

import { isEmptyProperty } from 'lib/components/PropertyFilters/utils'
import { projectLogic } from 'scenes/projectLogic'

import { AnyPropertyFilter } from '~/types'

import { featureFlagsUserBlastRadiusCreate } from './generated/api'

export interface RulesV2MatchCount {
    affected: number
    total: number
}

export interface RulesV2MatchCountLogicProps {
    /** The rule's targeting properties, serialized, so equal targeting shares one request. */
    propertiesKey: string
}

// The estimate is a slow query, and the view and the editor ask for the same targeting, so a recent answer is reused.
const CACHE_TTL_MS = 5 * 60 * 1000
const recentMatchCounts = new Map<string, { matchCount: RulesV2MatchCount; at: number }>()

/** Whether every condition is complete enough to count; an incomplete one would count as matching nobody. */
export function canCountRulesV2Matches(properties: AnyPropertyFilter[]): boolean {
    return !properties.some(isEmptyProperty)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface rulesV2MatchCountLogicValues {
    currentProjectId: number | null // projectLogic
    matchCount: RulesV2MatchCount | null
    matchCountFailed: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface rulesV2MatchCountLogicActions {
    loadMatchCount: () => {
        value: true
    }
    loadMatchCountFailure: () => {
        value: true
    }
    loadMatchCountSuccess: (matchCount: RulesV2MatchCount) => {
        matchCount: RulesV2MatchCount
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface rulesV2MatchCountLogicMeta {
    key: string
}

export type rulesV2MatchCountLogicType = MakeLogicType<
    rulesV2MatchCountLogicValues,
    rulesV2MatchCountLogicActions,
    RulesV2MatchCountLogicProps,
    rulesV2MatchCountLogicMeta
>

/**
 * How many persons a rule's targeting matches, from the estimate the v1 release conditions show. An estimate is a
 * hint, so a failure shows inline with a retry instead of a toast.
 */
export const rulesV2MatchCountLogic = kea<rulesV2MatchCountLogicType>([
    props({} as RulesV2MatchCountLogicProps),
    key(({ propertiesKey }) => propertiesKey),
    path((key) => ['products', 'feature_flags', 'frontend', 'rulesV2MatchCountLogic', key]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        loadMatchCount: true,
        loadMatchCountSuccess: (matchCount: RulesV2MatchCount) => ({ matchCount }),
        loadMatchCountFailure: true,
    }),
    reducers({
        matchCount: [
            null as RulesV2MatchCount | null,
            {
                loadMatchCount: () => null,
                loadMatchCountSuccess: (_, { matchCount }) => matchCount,
            },
        ],
        matchCountFailed: [
            false,
            {
                loadMatchCount: () => false,
                loadMatchCountFailure: () => true,
            },
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadMatchCount: async (_, breakpoint) => {
            const cacheKey = `${values.currentProjectId}:${props.propertiesKey}`
            const cached = recentMatchCounts.get(cacheKey)
            if (cached && Date.now() - cached.at < CACHE_TTL_MS) {
                actions.loadMatchCountSuccess(cached.matchCount)
                return
            }
            const properties = JSON.parse(props.propertiesKey) as AnyPropertyFilter[]
            let response
            try {
                response = await featureFlagsUserBlastRadiusCreate(String(values.currentProjectId), {
                    condition: { properties },
                    group_type_index: null,
                })
            } catch {
                breakpoint()
                actions.loadMatchCountFailure()
                return
            }
            const matchCount = { affected: response.affected, total: response.total }
            recentMatchCounts.set(cacheKey, { matchCount, at: Date.now() })
            breakpoint()
            actions.loadMatchCountSuccess(matchCount)
        },
    })),
    afterMount(({ actions, props }) => {
        if (canCountRulesV2Matches(JSON.parse(props.propertiesKey))) {
            actions.loadMatchCount()
        }
    }),
])
