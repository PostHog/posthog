export const featureFlagCodeAnalysisLogic = kea<featureFlagCodeAnalysisLogicType>([
    path((key) => ['products', 'feature_flags', 'frontend', 'featureFlagCodeAnalysisLogic', key]),
    props({} as FeatureFlagCodeAnalysisLogicProps),
    key((props) => props.id),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),

    actions({
        startAnalysis: true,
        startAnalysisSuccess: (analysis: FeatureFlagCodeAnalysisApi) => ({ analysis }),
        startAnalysisFailure: (error: string) => ({ error }),
        startAnalysisConflict: true,
        selectRepository: (repository: string) => ({ repository }),
        reportGitHubLinkClicked: true,
    }),

    loaders(({ props, values }) => ({
        target: [
            null as FeatureFlagCodeAnalysisTargetApi | null,
            {
                loadTarget: async () =>
                    await featureFlagsCodeAnalysisTargetRetrieve(String(values.currentProjectId), props.id),
            },
        ],
        analysis: [
            null as FeatureFlagCodeAnalysisApi | null,
            {
                loadAnalysis: async () => {
                    try {
                        return await featureFlagsCodeAnalysisRetrieve(String(values.currentProjectId), props.id)
                    } catch (error) {
                        // 404 means the flag was never analyzed, which is the empty state.
                        if (error instanceof ApiError && error.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
            },
        ],
    })),

    reducers({
        analysis: {
            startAnalysisSuccess: (_, { analysis }) => analysis,
        },
        // `analysis` is null both before the first load and when the flag was never analyzed.
        analysisLoaded: [
            false,
            {
                loadAnalysisSuccess: () => true,
                startAnalysisSuccess: () => true,
            },
        ],
        analysisLoadError: [
            null as string | null,
            {
                loadAnalysisSuccess: () => null,
                loadAnalysisFailure: (_, { error }) => error,
                startAnalysisSuccess: () => null,
            },
        ],
        startingAnalysis: [
            false,
            {
                startAnalysis: () => true,
                startAnalysisSuccess: () => false,
                startAnalysisFailure: () => false,
                startAnalysisConflict: () => false,
            },
        ],
        startError: [
            null as string | null,
            {
                startAnalysis: () => null,
                startAnalysisFailure: (_, { error }) => error,
            },
        ],
        selectedRepository: [
            null as string | null,
            {
                selectRepository: (_, { repository }) => repository,
            },
        ],
    }),

    selectors({
        repository: [
            (s) => [s.selectedRepository, s.target, s.analysis],
            (
                selectedRepository: string | null,
                target: FeatureFlagCodeAnalysisTargetApi | null,
                analysis: FeatureFlagCodeAnalysisApi | null
            ): string | null => selectedRepository ?? target?.repository ?? analysis?.repository ?? null,
        ],
        isRunning: [
            (s) => [s.analysis],
            (analysis: FeatureFlagCodeAnalysisApi | null): boolean => !!analysis && !analysis.is_terminal,
        ],
    }),

    listeners(({ actions, values, props, cache }) => {
        const startPolling = (): void => {
            cache.pollFailures = 0
            cache.disposables.add(() => {
                const id = setInterval(() => actions.loadAnalysis(), POLL_INTERVAL_MS)
                return () => clearInterval(id)
            }, POLL_KEY)
            cache.polling = true
        }
        const stopPolling = (): void => {
            cache.disposables.dispose(POLL_KEY)
            cache.polling = false
        }
        const followAnalysis = (analysis: FeatureFlagCodeAnalysisApi | null): void => {
            if (!analysis?.is_terminal) {
                if (analysis && !cache.polling) {
                    startPolling()
                }
                return
            }
            // Report only runs this page watched finish, not a result loaded from an earlier visit.
            if (cache.polling) {
                // pinned: analytics event names, renaming breaks dashboards
                posthog.capture(
                    analysis.run_status === 'completed'
                        ? 'feature flag code analysis completed'
                        : 'feature flag code analysis failed',
                    {
                        flag_id: props.id,
                        run_status: analysis.run_status,
                        reference_count: analysis.result?.references.length ?? null,
                    }
                )
            }
            stopPolling()
        }

        return {
            loadAnalysisSuccess: ({ analysis }) => {
                cache.pollFailures = 0
                followAnalysis(analysis)
            },
            loadAnalysisFailure: () => {
                // Tolerate transient errors, the run may still finish. Stop only when the endpoint keeps failing.
                cache.pollFailures = (cache.pollFailures ?? 0) + 1
                if (cache.pollFailures >= MAX_POLL_FAILURES) {
                    stopPolling()
                }
            },
            startAnalysis: async () => {
                const repository = values.repository
                try {
                    const analysis = await featureFlagsAnalyzeCodeCreate(
                        String(values.currentProjectId),
                        props.id,
                        repository ? { repository } : {}
                    )
                    posthog.capture('feature flag code analysis started', {
                        flag_id: props.id,
                        repository_source: values.target?.source ?? null,
                    })
                    actions.startAnalysisSuccess(analysis)
                } catch (error) {
                    // Another run is in progress, so follow that one instead of failing.
                    if (error instanceof ApiError && error.status === 409) {
                        actions.startAnalysisConflict()
                        return
                    }
                    const detail =
                        error instanceof ApiError && error.detail
                            ? error.detail
                            : "Couldn't start the analysis. Try again in a moment."
                    actions.startAnalysisFailure(detail)
                }
            },
            startAnalysisSuccess: ({ analysis }) => {
                // A new run restarts tracking even if the previous one was still being watched.
                stopPolling()
                followAnalysis(analysis)
            },
            startAnalysisConflict: () => {
                actions.loadAnalysis()
            },
            reportGitHubLinkClicked: () => {
                posthog.capture('feature flag code analysis github link clicked', { flag_id: props.id })
            },
        }
    }),

    afterMount(({ actions }) => {
        actions.loadTarget()
        actions.loadAnalysis()
    }),
])
