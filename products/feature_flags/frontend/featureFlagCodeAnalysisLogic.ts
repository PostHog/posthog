const POLL_INTERVAL_MS = 5000
const MAX_POLL_FAILURES = 3
const POLL_KEY = 'codeAnalysisPoll'
// Keep in sync with CODE_ANALYSIS_UNAVAILABLE_CODE in products/feature_flags/backend/api/code_analysis.py.
const UNAVAILABLE_ERROR_CODE = 'code_analysis_unavailable'

function isUnavailableError(error: unknown): boolean {
    return error instanceof ApiError && error.status === 404 && error.code === UNAVAILABLE_ERROR_CODE
}

