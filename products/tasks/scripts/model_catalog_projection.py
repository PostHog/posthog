"""Project the task run model catalog into TypeScript for the web app and the desktop app.

A renderer in the projection registry: it reads a pure-data Python module and returns the
checked-in ``*.generated.ts`` files, so the Python module stays the single authority and
the TypeScript sides are projections of it. It lives beside the catalog it projects,
since only this product reads it.

Both files come out of one template. The projection runner formats each through the
formatter of the workspace that owns it, oxfmt for the web app and Biome for the desktop
app, so the template only has to be valid TypeScript.

Only data is generated. The lookup built on it lives in
``products/desktop/packages/shared/src/model-catalog.ts`` and, for Python, in the source
module itself — behavior stays hand-written and tested, while the table that actually
changes has one home.

Registered in `tools/hogli-commands/hogli_commands/projections.py`; run
`hogli build:projections`.
"""

from __future__ import annotations

import json
import runpy
from pathlib import Path
from typing import Any

CATALOG_PY = Path(__file__).resolve().parents[1] / "backend" / "model_catalog.py"
WEB_OUTPUT = "products/tasks/frontend/modelCatalog.generated.ts"
DESKTOP_OUTPUT = "products/desktop/packages/shared/src/model-catalog.generated.ts"

HEADER = """// AUTO-GENERATED by products/tasks/scripts/model_catalog_projection.py from
// products/tasks/backend/model_catalog.py.
// Regenerate with `hogli build:projections`. Do not edit.
//
// The single definition of how a task agent run is configured: harness,
// runtime adapter, model, and reasoning effort, plus what each model
// costs. The backend validates a run against this same data, so a picker
// built on this file can only offer a selection the API will accept."""


def _s(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _n(value: float) -> str:
    """A number literal, written the way a hand-typed rate would be: `5`, not `5.0`."""
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def _array(values: tuple[str, ...]) -> str:
    return f"[{', '.join(_s(value) for value in values)}]"


def _union(values: tuple[str, ...]) -> str:
    return " | ".join(_s(value) for value in values)


def render_catalog(catalog: dict[str, Any]) -> str:
    i, semi = "  ", ";"
    adapters: tuple[str, ...] = catalog["RUNTIME_ADAPTERS"]
    providers: dict[str, str] = catalog["PROVIDER_BY_RUNTIME_ADAPTER"]
    defaults: dict[str, str] = catalog["DEFAULT_MODEL_BY_RUNTIME_ADAPTER"]
    fallbacks: dict[str, tuple[str, ...]] = catalog["FALLBACK_REASONING_EFFORTS_BY_RUNTIME_ADAPTER"]
    families: tuple[tuple[str, str, tuple[str, ...]], ...] = catalog["FAMILY_REASONING_EFFORTS"]
    models: tuple[Any, ...] = catalog["MODELS"]
    efforts: tuple[str, ...] = catalog["REASONING_EFFORTS"]
    effort_labels: dict[str, str] = catalog["REASONING_EFFORT_LABELS"]
    ladders: dict[str, tuple[Any, ...]] = catalog["CAPABILITY_LADDER_BY_RUNTIME_ADAPTER"]
    runtimes: tuple[str, ...] = catalog["RUNTIMES"]
    runtime_options: tuple[Any, ...] = catalog["RUNTIME_OPTIONS"]
    display_name = catalog["display_name_for_model"]
    multiplier_label = catalog["cost_multiplier_label"]
    cost_rates = catalog["format_cost_rates"]
    baseline_id = _s(catalog["COST_BASELINE_MODEL"])
    baseline_label = display_name(catalog["COST_BASELINE_MODEL"])
    baseline_label_literal = _s(baseline_label)

    def cost_lines(model: Any) -> list[str]:
        """The rates, and the two strings read off them, or nothing for an unpriced model.

        Both strings are rendered here rather than in TypeScript so a model quotes the same
        cost in the web app, Slack and the desktop app without three formatters agreeing by
        hand. Only the numbers stay machine-readable, for a caller estimating a spend.
        """
        if model.cost is None:
            return []
        return [
            f"{i}{i}cost: {{",
            f"{i}{i}{i}inputPerMtok: {_n(model.cost.input_per_mtok)},",
            f"{i}{i}{i}outputPerMtok: {_n(model.cost.output_per_mtok)},",
            f"{i}{i}}},",
            f"{i}{i}costMultiplier: {_s(multiplier_label(model.id))},",
            f"{i}{i}costSummary: {_s(cost_rates(model.cost))},",
        ]

    def model_entry(model: Any) -> str:
        return "\n".join(
            [
                f"{i}{{",
                f"{i}{i}id: {_s(model.id)},",
                f"{i}{i}runtimeAdapter: {_s(model.runtime_adapter)},",
                f"{i}{i}reasoningEfforts: {_array(model.reasoning_efforts)},",
                f"{i}{i}label: {_s(display_name(model.id))},",
                *([f"{i}{i}accessFlag: {_s(model.access_flag)},"] if model.access_flag else []),
                *cost_lines(model),
                *([f"{i}{i}supports1MContext: true,"] if model.supports_1m_context else []),
                *([f"{i}{i}supportsFastMode: true,"] if model.supports_fast_mode else []),
                *([f"{i}{i}retired: true,"] if model.retired else []),
                f"{i}}},",
            ]
        )

    def runtime_option_entry(option: Any) -> str:
        return "\n".join(
            [
                f"{i}{{",
                f"{i}{i}runtime: {_s(option.runtime)},",
                *([f"{i}{i}runtimeAdapter: {_s(option.runtime_adapter)},"] if option.runtime_adapter else []),
                f"{i}{i}label: {_s(option.label)},",
                f"{i}}},",
            ]
        )

    def ladder_entries(adapter: str) -> str:
        """One adapter's rungs, as an array of objects at depth 1."""
        notches = "\n".join(
            "\n".join(
                [
                    f"{i}{i}{{",
                    f"{i}{i}{i}model: {_s(notch.model)},",
                    f"{i}{i}{i}effort: {_s(notch.effort)},",
                    f"{i}{i}}},",
                ]
            )
            for notch in ladders[adapter]
        )
        return f"{i}{adapter}: [\n{notches}\n{i}],"

    model_entries = "\n".join(model_entry(model) for model in models)
    runtime_option_entries = "\n".join(runtime_option_entry(option) for option in runtime_options)
    effort_label_entries = "\n".join(f"{i}{effort}: {_s(effort_labels[effort])}," for effort in efforts)
    ladder_adapter_entries = "\n".join(ladder_entries(adapter) for adapter in adapters)
    provider_entries = "\n".join(f"{i}{adapter}: {_s(providers[adapter])}," for adapter in adapters)
    default_entries = "\n".join(f"{i}{adapter}: {_s(defaults[adapter])}," for adapter in adapters)
    fallback_entries = "\n".join(
        f"{i}{adapter}: {_array(fallbacks[adapter])}," for adapter in adapters if adapter in fallbacks
    )
    family_entries = "\n".join(
        f"{i}{{\n"
        f"{i}{i}runtimeAdapter: {_s(adapter)},\n"
        f"{i}{i}prefix: {_s(prefix)},\n"
        f"{i}{i}reasoningEfforts: {_array(family_efforts)},\n"
        f"{i}}},"
        for adapter, prefix, family_efforts in families
    )

    return f"""{HEADER}

export type RuntimeAdapter = {_union(adapters)}{semi}

export type Runtime = {_union(runtimes)}{semi}

export interface RuntimeOption {{
{i}runtime: Runtime{semi}
{i}/** Absent for Pi, which has no adapter. */
{i}runtimeAdapter?: RuntimeAdapter{semi}
{i}label: string{semi}
}}

/** What a harness picker shows. The runtime says which agent program runs the
    task; the adapter says which vendor protocol ACP speaks. A picker shows one
    flat list, so the two choices become one set of entries here. */
export const RUNTIME_OPTIONS: readonly RuntimeOption[] = [
{runtime_option_entries}
]{semi}

/** Thinking depths, shallowest first. */
export type ReasoningEffort = {_union(efforts)}{semi}

export const REASONING_EFFORTS: readonly ReasoningEffort[] = {_array(efforts)}{semi}

/** What a picker calls each depth. */
export const REASONING_EFFORT_LABELS: Record<ReasoningEffort, string> = {{
{effort_label_entries}
}}{semi}

/** A value for each runtime adapter. */
export type ByRuntimeAdapter<T> = Record<RuntimeAdapter, T>{semi}

/** Efforts per adapter, absent where the adapter has no fallback. */
type FallbackEfforts = Partial<ByRuntimeAdapter<readonly ReasoningEffort[]>>{semi}

export interface ModelCost {{
{i}inputPerMtok: number{semi}
{i}outputPerMtok: number{semi}
}}

export interface CatalogModel {{
{i}id: string{semi}
{i}runtimeAdapter: RuntimeAdapter{semi}
{i}/** Empty for a model with no effort control: render no dropdown. */
{i}reasoningEfforts: readonly ReasoningEffort[]{semi}
{i}/**
{i} * What a picker shows. Resolved when this file is generated, so every
{i} * surface names a model the same way without carrying a formatter.
{i} */
{i}label: string{semi}
{i}/**
{i} * Feature flag a person needs before a picker offers this model. Absent
{i} * means generally available. Governs display only — the server decides
{i} * whether a run may use it.
{i} */
{i}accessFlag?: string{semi}
{i}/**
{i} * List price in US dollars per million tokens. Absent for a model no
{i} * public price list covers, which a picker shows with no cost at all.
{i} */
{i}cost?: ModelCost{semi}
{i}/**
{i} * Per-token cost against {baseline_label}, ready to render: `2.5×`,
{i} * `≈0.55×`. Prefixed when input and output rates diverge enough that one
{i} * number flatters either. Absent whenever `cost` is.
{i} */
{i}costMultiplier?: string{semi}
{i}/**
{i} * The rates behind the multiplier, ready to render. Absent whenever
{i} * `cost` is.
{i} */
{i}costSummary?: string{semi}
{i}/**
{i} * Runs with the 1M-token context window. Absent means it does not, and a
{i} * picker offers no window choice.
{i} */
{i}supports1MContext?: boolean{semi}
{i}/**
{i} * Runs in fast mode. Absent means it does not, and a picker offers no
{i} * fast-mode toggle.
{i} */
{i}supportsFastMode?: boolean{semi}
{i}/**
{i} * Superseded: no picker offers it, and a session already pinned to it
{i} * still runs and still reads its name and cost from here.
{i} */
{i}retired?: boolean{semi}
}}

/** The model `1×` refers to. */
export const COST_BASELINE_MODEL = {baseline_id}{semi}

export const COST_BASELINE_LABEL = {baseline_label_literal}{semi}

/** Which vendor API each runtime adapter speaks. */
export const PROVIDER_BY_RUNTIME_ADAPTER: ByRuntimeAdapter<string> = {{
{provider_entries}
}}{semi}

export const RUNTIME_ADAPTERS: readonly RuntimeAdapter[] = {_array(adapters)}{semi}

export const MODELS: readonly CatalogModel[] = [
{model_entries}
]{semi}

/** The model a run uses when it pins none. */
export const DEFAULT_MODEL_BY_RUNTIME_ADAPTER: ByRuntimeAdapter<string> = {{
{default_entries}
}}{semi}

export interface CapabilityNotch {{
{i}model: string{semi}
{i}effort: ReasoningEffort{semi}
}}

type CapabilityLadders = ByRuntimeAdapter<readonly CapabilityNotch[]>{semi}

/** The Faster → Smarter rungs each harness offers, cheapest first. Filter them
    against what the gateway serves before rendering, so a rung naming a retired
    model drops out instead of becoming a stop that fails on send. */
export const CAPABILITY_LADDER_BY_RUNTIME_ADAPTER: CapabilityLadders = {{
{ladder_adapter_entries}
}}{semi}

export interface ModelFamily {{
{i}runtimeAdapter: RuntimeAdapter{semi}
{i}prefix: string{semi}
{i}reasoningEfforts: readonly ReasoningEffort[]{semi}
}}

// Depths a whole family exposes, used when no exact id matches. OpenAI ships
// vendor-flavoured variants the gateway never lists (`gpt-5.5-codex`), and a
// local session can drive one. The longest matching prefix wins, so the
// declaration order below is free.
export const FAMILY_REASONING_EFFORTS: readonly ModelFamily[] = [
{family_entries}
]{semi}

// What a runtime accepts for a model neither an id nor a family claims.
// Codex passes any `gpt-*` identifier through, so an id the gateway starts
// serving before it is listed here still runs. Claude is absent on
// purpose: an unnamed model there yields no efforts, which is what makes
// validation reject it.
export const FALLBACK_REASONING_EFFORTS: FallbackEfforts = {{
{fallback_entries}
}}{semi}
"""


def render() -> dict[str, str]:
    # runpy.run_path loads the module by filesystem path, bypassing the import machinery and
    # therefore products/__init__.py and the Django settings behind it. Anything
    # model_catalog.py cannot satisfy from the standard library raises here, failing loudly.
    catalog = runpy.run_path(str(CATALOG_PY))
    rendered = render_catalog(catalog)
    return {WEB_OUTPUT: rendered, DESKTOP_OUTPUT: rendered}
