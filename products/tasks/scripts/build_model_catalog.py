#!/usr/bin/env python3
"""Project the task run model catalog into TypeScript for the web app and the desktop app.

Same pattern as ``bin/build-mcp-oauth-scopes.py``: a codegen script that reads a pure-data
Python module and writes a checked-in ``*.generated.ts``, so the Python module stays the
single authority and the TypeScript sides are projections of it. It lives beside the
catalog it projects rather than in ``bin/``, since only this product reads or writes it —
the same placement as ``products/posthog_ai/scripts/build_skills.py``.

Two files come out of one template because the two workspaces run different formatters —
the web app runs oxfmt (four spaces, single quotes, no semicolons, 120 columns) and the
desktop app runs Biome (two spaces, double quotes, semicolons, 80 columns). Each file is
emitted in the shape its own formatter would produce, so a later ``pnpm format`` never
turns generated output into a diff. Objects are written one property per line, which both
formatters preserve regardless of width; arrays and unions are wrapped against the target
width, because both formatters collapse those whenever they fit.

Emitting that shape rather than shelling out to each formatter is a deliberate trade. It
costs a small amount of formatter emulation here, and it buys a ``render()`` whose output
is byte-exact, which is what lets the drift test compare the checked-in files against this
module with no Node in the loop. ``check_fits`` is the guard on that bargain: a line the
target formatter would rewrap fails the build instead of drifting silently.

Only data is generated. The lookup built on it lives in
``products/desktop/packages/shared/src/model-catalog.ts`` and, for Python, in the source
module itself — behavior stays hand-written and tested, while the table that actually
changes has one home.

Run via hogli: `hogli build:task-model-catalog` (also runs as part of `build:openapi`).
See `hogli.yaml`.
"""
# ruff: noqa: T201

from __future__ import annotations

import sys
import runpy
from dataclasses import dataclass
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
CATALOG_PY = REPO_ROOT / "products" / "tasks" / "backend" / "model_catalog.py"
WEB_OUTPUT = REPO_ROOT / "products" / "tasks" / "frontend" / "modelCatalog.generated.ts"
DESKTOP_OUTPUT = REPO_ROOT / "products" / "desktop" / "packages" / "shared" / "src" / "model-catalog.generated.ts"

HEADER = """// AUTO-GENERATED by products/tasks/scripts/build_model_catalog.py from
// products/tasks/backend/model_catalog.py.
// Regenerate with `hogli build:task-model-catalog`. Do not edit.
//
// The single definition of a task agent run's triple: runtime adapter,
// model, and reasoning effort. The backend validates a run against this
// same data, so a picker built on this file can only offer a selection
// the API will accept."""


@dataclass(frozen=True)
class Style:
    """How one workspace's formatter wants generated TypeScript to look."""

    indent: str
    quote: str
    semi: str
    width: int

    def s(self, value: str) -> str:
        """A string literal. Catalog values are lowercase ids: letters, digits, `-./@` only."""
        if self.quote in value or "\\" in value:
            raise RuntimeError(f"unexpected character in catalog value: {value!r}")
        return f"{self.quote}{value}{self.quote}"

    def array(self, values: tuple[str, ...], *, prefix: str, suffix: str, depth: int) -> str:
        """An array literal, wrapped one item per line when the single-line form is too wide."""
        pad = self.indent * depth
        items = [self.s(value) for value in values]
        single = f"{pad}{prefix}[{', '.join(items)}]{suffix}"
        if len(single) <= self.width:
            return single
        inner = "".join(f"{pad}{self.indent}{item},\n" for item in items)
        return f"{pad}{prefix}[\n{inner}{pad}]{suffix}"

    def union(self, values: tuple[str, ...], *, prefix: str) -> str:
        """A string-literal union, broken onto leading-pipe lines when too wide."""
        items = [self.s(value) for value in values]
        single = f"{prefix}{' | '.join(items)}{self.semi}"
        if len(single) <= self.width:
            return single
        broken = "".join(f"{self.indent}| {item}\n" for item in items)
        return f"{prefix.rstrip()}\n{broken.rstrip()}{self.semi}"


OXFMT = Style(indent=" " * 4, quote="'", semi="", width=120)
BIOME = Style(indent=" " * 2, quote='"', semi=";", width=80)


def render(catalog: dict[str, Any], style: Style) -> str:
    i, semi = style.indent, style.semi
    adapters: tuple[str, ...] = catalog["RUNTIME_ADAPTERS"]
    providers: dict[str, str] = catalog["PROVIDER_BY_RUNTIME_ADAPTER"]
    defaults: dict[str, str] = catalog["DEFAULT_MODEL_BY_RUNTIME_ADAPTER"]
    fallbacks: dict[str, tuple[str, ...]] = catalog["FALLBACK_REASONING_EFFORTS_BY_RUNTIME_ADAPTER"]
    families: tuple[tuple[str, str, tuple[str, ...]], ...] = catalog["FAMILY_REASONING_EFFORTS"]
    models: tuple[Any, ...] = catalog["MODELS"]
    efforts: tuple[str, ...] = catalog["REASONING_EFFORTS"]

    model_entries = "\n".join(
        f"{i}{{\n"
        f"{i}{i}id: {style.s(model.id)},\n"
        f"{i}{i}runtimeAdapter: {style.s(model.runtime_adapter)},\n"
        f"{style.array(model.reasoning_efforts, prefix='reasoningEfforts: ', suffix=',', depth=2)}\n"
        f"{i}}},"
        for model in models
    )
    provider_entries = "\n".join(f"{i}{adapter}: {style.s(providers[adapter])}," for adapter in adapters)
    default_entries = "\n".join(f"{i}{adapter}: {style.s(defaults[adapter])}," for adapter in adapters)
    fallback_entries = "\n".join(
        style.array(fallbacks[adapter], prefix=f"{adapter}: ", suffix=",", depth=1)
        for adapter in adapters
        if adapter in fallbacks
    )
    family_entries = "\n".join(
        f"{i}{{\n"
        f"{i}{i}runtimeAdapter: {style.s(adapter)},\n"
        f"{i}{i}prefix: {style.s(prefix)},\n"
        f"{style.array(family_efforts, prefix='reasoningEfforts: ', suffix=',', depth=2)}\n"
        f"{i}}},"
        for adapter, prefix, family_efforts in families
    )

    return f"""{HEADER}

{style.union(adapters, prefix="export type RuntimeAdapter = ")}

/** Thinking depths, shallowest first. */
{style.union(efforts, prefix="export type ReasoningEffort = ")}

{style.array(efforts, prefix="export const REASONING_EFFORTS: readonly ReasoningEffort[] = ", suffix=semi, depth=0)}

/** A value for each runtime adapter. */
export type ByRuntimeAdapter<T> = Record<RuntimeAdapter, T>{semi}

/** Efforts per adapter, absent where the adapter has no fallback. */
type FallbackEfforts = Partial<ByRuntimeAdapter<readonly ReasoningEffort[]>>{semi}

export interface CatalogModel {{
{i}id: string{semi}
{i}runtimeAdapter: RuntimeAdapter{semi}
{i}/** Empty for a model with no effort control: render no dropdown. */
{i}reasoningEfforts: readonly ReasoningEffort[]{semi}
}}

/** Which vendor API each runtime adapter speaks. */
export const PROVIDER_BY_RUNTIME_ADAPTER: ByRuntimeAdapter<string> = {{
{provider_entries}
}}{semi}

{style.array(adapters, prefix="export const RUNTIME_ADAPTERS: readonly RuntimeAdapter[] = ", suffix=semi, depth=0)}

export const MODELS: readonly CatalogModel[] = [
{model_entries}
]{semi}

/** The model a run uses when it pins none. */
export const DEFAULT_MODEL_BY_RUNTIME_ADAPTER: ByRuntimeAdapter<string> = {{
{default_entries}
}}{semi}

export interface ModelFamily {{
{i}runtimeAdapter: RuntimeAdapter{semi}
{i}prefix: string{semi}
{i}reasoningEfforts: readonly ReasoningEffort[]{semi}
}}

// Depths a whole family exposes, used when no exact id matches. OpenAI ships
// vendor-flavoured variants the gateway never lists (`gpt-5.5-codex`), and a
// local session can drive one. The longest matching prefix wins, so the
// declaration order below is free.
export const FAMILY_REASONING_EFFORTS: readonly ModelFamily[] = [
{family_entries}
]{semi}

// What a runtime accepts for a model neither an id nor a family claims.
// Codex passes any `gpt-*` identifier through, so an id the gateway starts
// serving before it is listed here still runs. Claude is absent on
// purpose: an unnamed model there yields no efforts, which is what makes
// validation reject it.
export const FALLBACK_REASONING_EFFORTS: FallbackEfforts = {{
{fallback_entries}
}}{semi}
"""


def check_fits(rendered: str, style: Style, output: Path) -> None:
    """Fail on a line the target formatter would rewrap.

    Every line here is already in the shape its formatter produces, which is what keeps a
    ``pnpm format`` run from turning generated output into a diff. A model id long enough
    to push a line past the column limit breaks that quietly, so it stops the build
    instead — the fix is to shorten the emitted shape, not to accept the drift.
    """
    too_long = [line for line in rendered.splitlines() if len(line) > style.width]
    if too_long:
        raise RuntimeError(
            f"{output.name}: {len(too_long)} line(s) exceed {style.width} columns and would be "
            f"rewrapped by the formatter, e.g.\n  {too_long[0]}"
        )


def main() -> int:
    # runpy.run_path loads the module by filesystem path, bypassing the import machinery and
    # therefore products/__init__.py and the Django settings behind it. Anything
    # model_catalog.py cannot satisfy from the standard library raises here, failing loudly.
    catalog = runpy.run_path(str(CATALOG_PY))
    model_count = len(catalog["MODELS"])

    for output, style in ((WEB_OUTPUT, OXFMT), (DESKTOP_OUTPUT, BIOME)):
        rendered = render(catalog, style)
        check_fits(rendered, style, output)
        output.parent.mkdir(parents=True, exist_ok=True)
        if output.exists() and output.read_text() == rendered:
            print(f"{output.relative_to(REPO_ROOT)} already up to date ({model_count} models)")
            continue
        output.write_text(rendered)
        print(f"wrote {output.relative_to(REPO_ROOT)} ({model_count} models)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
