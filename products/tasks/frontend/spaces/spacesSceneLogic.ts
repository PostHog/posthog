export type spacesSceneLogicType = MakeLogicType<
    spacesSceneLogicValues,
    spacesSceneLogicActions,
    Record<string, any>,
    spacesSceneLogicMeta
>

export const spacesSceneLogic = kea<spacesSceneLogicType>([
    path(['products', 'tasks', 'spaces', 'spacesSceneLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            todaySpacesLogic,
            ['sortedSpaces', 'spacesLoading', 'spacesUnavailable'],
        ],
        actions: [todaySpacesLogic, ['loadSpaces', 'loadSpacesSuccess', 'loadSpacesFailure']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        toggleStar: (spaceId: string, starred: boolean) => ({ spaceId, starred }),
        starFailed: (spaceId: string) => ({ spaceId }),
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        pendingSpaceIds: [
            [] as string[],
            {
                toggleStar: (state, { spaceId }) => [...state, spaceId],
                starFailed: (state, { spaceId }) => state.filter((id) => id !== spaceId),
                loadSpacesSuccess: () => [],
                loadSpacesFailure: () => [],
            },
        ],
    }),
    selectors({
        lists: [
            (s) => [s.sortedSpaces, s.search],
            (sortedSpaces: ChannelDTOApi[], search: string): SpacesIndexLists => spacesIndexLists(sortedSpaces, search),
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [{ key: Scene.TaskSpaces, name: 'Spaces', path: urls.taskSpaces(), iconType: 'task' }],
        ],
    }),
    listeners(({ actions, values }) => ({
        toggleStar: async ({ spaceId, starred }) => {
            try {
                await taskChannelsStarCreate(String(values.currentTeamId), spaceId, { starred })
                actions.loadSpaces()
            } catch {
                toast.error({ title: `Couldn’t ${starred ? 'star' : 'unstar'} this space. Try again.` })
                actions.starFailed(spaceId)
            }
        },
    })),
])
