import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { toast } from '@posthog/quill'

import { Scene } from 'scenes/sceneTypes'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { starredSpaces, todaySpacesLogic } from '~/layout/today/todaySpacesLogic'
import { Breadcrumb } from '~/types'

import { taskChannelsStarCreate } from '../generated/api'
import { ChannelDTOApi } from '../generated/api.schemas'

export interface SpacesIndexLists {
    starred: ChannelDTOApi[]
    rest: ChannelDTOApi[]
}

export function spacesIndexLists(spaces: ChannelDTOApi[], search: string): SpacesIndexLists {
    const needle = search.trim().toLowerCase()
    const shown = needle ? spaces.filter((space) => space.name.toLowerCase().includes(needle)) : spaces
    const starred = starredSpaces(shown)
    const starredIds = new Set(starred.map((space) => space.id))
    return { starred, rest: shown.filter((space) => !starredIds.has(space.id)) }
}

