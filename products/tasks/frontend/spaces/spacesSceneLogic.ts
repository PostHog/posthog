const SPACE_PRESENCE_FETCH_LIMIT = 100
const SPACE_PRESENCE_POLL_INTERVAL_MS = 90_000

export interface SpacesIndexLists {
    starred: ChannelDTOApi[]
    rest: ChannelDTOApi[]
}

export function spacesIndexLists(spaces: ChannelDTOApi[], search: string): SpacesIndexLists {
    const needle = search.trim().toLowerCase()
    const shown = needle ? spaces.filter((space) => space.name.toLowerCase().includes(needle)) : spaces
    const starred = starredSpaces(shown)
    const starredIds = new Set(starred.map((space) => space.id))
    return { starred, rest: shown.filter((space) => !starredIds.has(space.id)) }
}

