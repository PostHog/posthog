export type spaceLoopSceneLogicType = MakeLogicType<
    spaceLoopSceneLogicValues,
    spaceLoopSceneLogicActions,
    SpaceLoopSceneLogicProps,
    spaceLoopSceneLogicMeta
>

export const spaceLoopSceneLogic = kea<spaceLoopSceneLogicType>([
    path((key) => ['products', 'tasks', 'spaces', 'loops', 'spaceLoopSceneLogic', key]),
    props({} as SpaceLoopSceneLogicProps),
    key((props) => `${props.id}/${props.loopId}`),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], teamLogic, ['currentTeamId'], todaySpacesLogic, ['spaces']],
    })),
    actions({
        setEnabled: (enabled: boolean) => ({ enabled }),
        enabledSaved: (enabled: boolean) => ({ enabled }),
        enabledSaveFailed: true,
        runNow: true,
        runFinished: true,
        copyLink: true,
        setDeleteOpen: (open: boolean) => ({ open }),
        deleteLoop: true,
        deleteFinished: true,
    }),
    loaders(({ props, values }) => ({
        loop: [
            null as SpaceLoop | null,
            {
                loadLoop: async () => (values.backend ? await retrieveSpaceLoop(values.backend, props.loopId) : null),
            },
        ],
        runs: [
            null as SpaceLoopRun[] | null,
            {
                loadRuns: async () => (values.backend ? await listSpaceLoopRuns(values.backend, props.loopId) : null),
            },
        ],
    })),
    reducers({
        loop: {
            enabledSaved: (state, { enabled }) => (state ? spaceLoopWithEnabled(state, enabled) : state),
        },
        loopUnavailable: [false, { loadLoop: () => false, loadLoopFailure: () => true }],
        loopMissing: [
            false,
            {
                loadLoop: () => false,
                loadLoopFailure: (_, { errorObject }) => errorObject?.status === 404,
            },
        ],
        savingEnabled: [false, { setEnabled: () => true, enabledSaved: () => false, enabledSaveFailed: () => false }],
        runningNow: [false, { runNow: () => true, runFinished: () => false }],
        deleting: [false, { deleteLoop: () => true, deleteFinished: () => false }],
        deleteOpen: [false, { setDeleteOpen: (_, { open }) => open, deleteFinished: () => false }],
    }),
    selectors({
        workflowBacked: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.LOOPS_HOG_FLOWS],
        ],
        backend: [
            (s) => [s.currentTeamId, s.workflowBacked],
            (currentTeamId: number | null, workflowBacked: boolean): SpaceLoopsBackend | null =>
                currentTeamId ? { projectId: String(currentTeamId), workflowBacked } : null,
        ],
        spaceName: [
            (s) => [s.spaces, (_, props) => props],
            (spaces: ChannelDTOApi[], props: SpaceLoopSceneLogicProps): string => {
                const space = spaces.find((candidate) => candidate.id === props.id)
                return space ? spaceLabel(space) : 'Space'
            },
        ],
        breadcrumbs: [
            (s) => [s.spaceName, s.loop, (_, props) => props],
            (spaceName: string, loop: SpaceLoop | null, props: SpaceLoopSceneLogicProps): Breadcrumb[] => [
                {
                    key: [Scene.TaskSpace, props.id],
                    name: spaceName,
                    path: urls.taskSpace(props.id),
                    iconType: 'task',
                },
                {
                    key: [Scene.TaskSpace, `${props.id}/loops`],
                    name: 'Loops',
                    path: urls.taskSpaceLoops(props.id),
                },
                {
                    key: [Scene.TaskSpaceLoop, props.loopId],
                    name: loop ? loop.name || 'Untitled loop' : 'Loop',
                },
            ],
        ],
    }),
    listeners(({ actions, props, values }) => ({
        setEnabled: async ({ enabled }) => {
            if (!values.backend) {
                actions.enabledSaveFailed()
                return
            }
            try {
                await setSpaceLoopEnabled(values.backend, props.loopId, enabled)
                actions.enabledSaved(enabled)
                // pinned: analytics event name, renaming breaks dashboards
                posthog.capture('space loop enabled toggled', { enabled, surface: 'detail' })
            } catch {
                actions.enabledSaveFailed()
                toast.error({ title: enabled ? 'Couldn’t resume this loop' : 'Couldn’t pause this loop' })
            }
        },
        runNow: async () => {
            try {
                const blockedReason = values.backend ? await runSpaceLoop(values.backend, props.loopId) : 'unknown'
                if (blockedReason) {
                    toast.error({ title: 'Run not started', description: spaceLoopRunBlockedMessage(blockedReason) })
                } else {
                    toast.success({ title: 'Run started', description: 'It shows in the run history once it starts.' })
                    // pinned: analytics event name, renaming breaks dashboards
                    posthog.capture('space loop run started')
                    actions.loadRuns()
                }
            } catch {
                toast.error({ title: 'Couldn’t start a run. Try again.' })
            }
            actions.runFinished()
        },
        copyLink: async () => {
            await copyToClipboard(`${window.location.origin}${urls.taskSpaceLoop(props.id, props.loopId)}`, 'loop link')
        },
        deleteLoop: async () => {
            try {
                if (!values.backend) {
                    throw new Error('No project')
                }
                await deleteSpaceLoop(values.backend, props.loopId)
                toast.success({ title: 'Loop deleted' })
                // pinned: analytics event name, renaming breaks dashboards
                posthog.capture('space loop deleted')
                router.actions.push(urls.taskSpaceLoops(props.id))
            } catch {
                toast.error({ title: 'Couldn’t delete this loop. Try again.' })
            }
            actions.deleteFinished()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadLoop()
        actions.loadRuns()
    }),
])
