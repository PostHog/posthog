export const spaceLoopSceneLogic = kea<spaceLoopSceneLogicType>([
    path((key) => ['products', 'tasks', 'spaces', 'loops', 'spaceLoopSceneLogic', key]),
    props({} as SpaceLoopSceneLogicProps),
    key((props) => `${props.id}/${props.loopId}`),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], teamLogic, ['currentTeamId'], todaySpacesLogic, ['spaceNames']],
    })),
    actions({
        setEnabled: (enabled: boolean) => ({ enabled }),
        enabledSaved: (enabled: boolean) => ({ enabled }),
        enabledSaveFailed: true,
        runNow: true,
        runFinished: true,
        copyLink: true,
        setDeleteOpen: (open: boolean) => ({ open }),
        deleteLoop: true,
        deleteFinished: true,
        backendChanged: true,
    }),
    loaders(({ props, values }) => ({
        loop: [
            null as SpaceLoop | null,
            {
                loadLoop: async () => {
                    if (!values.backend) {
                        throw new Error('No project')
                    }
                    return await retrieveSpaceLoop(values.backend, props.loopId)
                },
            },
        ],
        runs: [
            null as SpaceLoopRun[] | null,
            {
                loadRuns: async () => {
                    if (!values.backend) {
                        throw new Error('No project')
                    }
                    return await listSpaceLoopRuns(values.backend, props.loopId)
                },
            },
        ],
    })),
    reducers({
        loop: {
            enabledSaved: (state, { enabled }) => (state ? spaceLoopWithEnabled(state, enabled) : state),
            backendChanged: () => null,
        },
        runs: {
            backendChanged: () => null,
        },
        loopUnavailable: [false, { loadLoop: () => false, loadLoopFailure: () => true }],
        loopMissing: [
            false,
            {
                loadLoop: () => false,
                loadLoopFailure: (_, { errorObject }) => errorObject?.status === 404,
            },
        ],
        savingEnabled: [false, { setEnabled: () => true, enabledSaved: () => false, enabledSaveFailed: () => false }],
        runningNow: [false, { runNow: () => true, runFinished: () => false }],
        deleting: [false, { deleteLoop: () => true, deleteFinished: () => false }],
        deleteOpen: [false, { setDeleteOpen: (_, { open }) => open, deleteFinished: () => false }],
    }),
    selectors({
        backend: [
            (s) => [s.featureFlags, s.currentTeamId],
            (featureFlags: FeatureFlagsSet, currentTeamId: number | null): SpaceLoopsBackend | null =>
                spaceLoopsBackend(featureFlags, currentTeamId),
        ],
        // Loads wait for the team and the loops flag, and run again when the loop backend changes, because a loop
        // id from one backend means nothing to the other.
        loadKey: [
            (s) => [s.backend, s.featureFlags],
            (backend: SpaceLoopsBackend | null, featureFlags: FeatureFlagsSet): string | null =>
                backend && featureFlags[FEATURE_FLAGS.LOOPS] ? `${backend.projectId}:${backend.workflowBacked}` : null,
        ],
        spaceName: [
            (s) => [s.spaceNames, (_, props) => props],
            (spaceNames: Record<string, string>, props: SpaceLoopSceneLogicProps): string =>
                spaceNames[props.id] ?? 'Space',
        ],
        breadcrumbs: [
            (s) => [s.spaceName, s.loop, (_, props) => props],
            (spaceName: string, loop: SpaceLoop | null, props: SpaceLoopSceneLogicProps): Breadcrumb[] => [
                {
                    key: [Scene.TaskSpace, props.id],
                    name: spaceName,
                    path: urls.taskSpace(props.id),
                    iconType: 'task',
                },
                {
                    key: [Scene.TaskSpace, `${props.id}/loops`],
                    name: 'Loops',
                    path: urls.taskSpaceLoops(props.id),
                },
                {
                    key: [Scene.TaskSpaceLoop, props.loopId],
                    name: loop ? spaceLoopName(loop) : 'Loop',
                },
            ],
        ],
    }),
    listeners(({ actions, props, values, cache }) => ({
        setEnabled: async ({ enabled }) => {
            const saved = values.backend
                ? await saveSpaceLoopEnabled(values.backend, props.loopId, enabled, 'detail')
                : false
            if (saved) {
                actions.enabledSaved(enabled)
            } else {
                actions.enabledSaveFailed()
            }
        },
        runNow: async (_, breakpoint) => {
            const backend = values.backend
            if (!backend) {
                actions.runFinished()
                return
            }
            // The key lives until the server answers clearly, so a retry after a timeout cannot start a second run.
            cache.runIdempotencyKey ??= crypto.randomUUID()
            let started = false
            try {
                const blockedReason = await runSpaceLoop(backend, props.loopId, cache.runIdempotencyKey)
                cache.runIdempotencyKey = null
                if (blockedReason) {
                    toast.error({ title: 'Run not started', description: spaceLoopRunBlockedMessage(blockedReason) })
                } else {
                    started = true
                    toast.success({ title: 'Run started', description: 'It shows in the run history once it starts.' })
                    // pinned: analytics event name, renaming breaks dashboards
                    posthog.capture('space loop run started')
                    actions.loadRuns()
                }
            } catch (error) {
                const status = (error as { status?: number }).status
                if (status === undefined || status === 504 || status === 409) {
                    toast.error({
                        title: 'The run might have started',
                        description: 'Check the run history before you try again.',
                    })
                    actions.loadRuns()
                } else {
                    cache.runIdempotencyKey = null
                    toast.error({
                        title: 'Couldn’t start a run',
                        description: readableErrorMessage(error) ?? 'Try again.',
                    })
                }
            }
            actions.runFinished()
            if (started) {
                // A workflow creates the run's task after the run is queued, so look again a moment later.
                await breakpoint(5000)
                actions.loadRuns()
            }
        },
        copyLink: async () => {
            const outcome = await writeToClipboard(
                urls.absolute(urls.currentProject(urls.taskSpaceLoop(props.id, props.loopId)))
            )
            if (outcome === 'copied') {
                toast.success({ title: 'Link copied' })
            } else {
                toast.error({ title: 'Couldn’t copy the link. Copy it from the address bar instead.' })
            }
        },
        deleteLoop: async () => {
            if (values.backend) {
                try {
                    await deleteSpaceLoop(values.backend, props.loopId)
                    toast.success({ title: 'Loop deleted' })
                    // pinned: analytics event name, renaming breaks dashboards
                    posthog.capture('space loop deleted')
                    router.actions.push(urls.taskSpaceLoops(props.id))
                } catch (error) {
                    toast.error({
                        title: 'Couldn’t delete this loop',
                        description: readableErrorMessage(error) ?? 'Try again.',
                    })
                }
            }
            actions.deleteFinished()
        },
    })),
    subscriptions(({ actions }) => ({
        loadKey: (loadKey: string | null, previousKey: string | null | undefined) => {
            if (!loadKey) {
                return
            }
            if (previousKey) {
                actions.backendChanged()
            }
            actions.loadLoop()
            actions.loadRuns()
        },
    })),
])
