export type spaceLoopsLogicType = MakeLogicType<
    spaceLoopsLogicValues,
    spaceLoopsLogicActions,
    SpaceSceneLogicProps,
    spaceLoopsLogicMeta
>

export const spaceLoopsLogic = kea<spaceLoopsLogicType>([
    path((id) => ['products', 'tasks', 'spaces', 'loops', 'spaceLoopsLogic', id]),
    props({} as SpaceSceneLogicProps),
    key((props) => props.id),
    connect((props: SpaceSceneLogicProps) => ({
        values: [featureFlagLogic, ['featureFlags'], spaceSceneLogic(props), ['space'], teamLogic, ['currentTeamId']],
        actions: [composerSeedLogic({ panelId: spaceComposerPanelId(props.id) }), ['setSeed']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setHidePaused: (hidePaused: boolean) => ({ hidePaused }),
        setLoopEnabled: (loopId: string, enabled: boolean) => ({ loopId, enabled }),
        loopEnabledSaved: (loopId: string, enabled: boolean) => ({ loopId, enabled }),
        loopEnabledSaveFailed: (loopId: string) => ({ loopId }),
        setTemplateCategory: (category: SpaceLoopTemplateCategory) => ({ category }),
        applyTemplate: (template: SpaceLoopTemplate) => ({ template }),
        setBuilderDraft: (draft: string) => ({ draft }),
        focusBuilder: true,
        submitBuilder: true,
        backendChanged: true,
        setLimitReason: (limitReason: string | null) => ({ limitReason }),
        setVisibilityFilter: (visibility: SpaceLoopVisibilityFilter) => ({ visibility }),
    }),
    loaders(({ actions, props, values }) => ({
        loops: [
            null as SpaceLoop[] | null,
            {
                loadLoops: async () => {
                    if (!values.backend) {
                        throw new Error('No project')
                    }
                    const { loops, limitReason } = await listSpaceLoops(values.backend, props.id)
                    actions.setLimitReason(limitReason)
                    return loops
                },
            },
        ],
    })),
    reducers({
        loops: {
            backendChanged: () => null,
            loopEnabledSaved: (state, { loopId, enabled }) =>
                state?.map((loop) => (loop.id === loopId ? spaceLoopWithEnabled(loop, enabled) : loop)) ?? null,
        },
        loopsUnavailable: [false, { loadLoops: () => false, loadLoopsFailure: () => true }],
        search: ['', { setSearch: (_, { search }) => search }],
        limitReason: [null as string | null, { setLimitReason: (_, { limitReason }) => limitReason }],
        visibilityFilter: [
            'all' as SpaceLoopVisibilityFilter,
            { setVisibilityFilter: (_, { visibility }) => visibility },
        ],
        hidePaused: [false, { setHidePaused: (_, { hidePaused }) => hidePaused }],
        pendingLoopIds: [
            [] as string[],
            {
                setLoopEnabled: (state, { loopId }) => [...state, loopId],
                loopEnabledSaved: (state, { loopId }) => state.filter((id) => id !== loopId),
                loopEnabledSaveFailed: (state, { loopId }) => state.filter((id) => id !== loopId),
            },
        ],
        templateCategory: [
            'engineering' as SpaceLoopTemplateCategory,
            { setTemplateCategory: (_, { category }) => category },
        ],
        builderDraft: [
            '',
            {
                setBuilderDraft: (_, { draft }) => draft,
            },
        ],
        builderFocusRequest: [0, { focusBuilder: (state) => state + 1 }],
    }),
    selectors({
        backend: [
            (s) => [s.featureFlags, s.currentTeamId],
            (featureFlags: FeatureFlagsSet, currentTeamId: number | null): SpaceLoopsBackend | null =>
                spaceLoopsBackend(featureFlags, currentTeamId),
        ],
        // A loop id from one backend means nothing to the other, so the list reloads when the backend changes.
        loadKey: [
            (s) => [s.backend],
            (backend: SpaceLoopsBackend | null): string | null =>
                backend ? `${backend.projectId}:${backend.workflowBacked}` : null,
        ],
        filteredLoops: [
            (s) => [s.loops, s.search, s.hidePaused, s.visibilityFilter],
            (
                loops: SpaceLoop[] | null,
                search: string,
                hidePaused: boolean,
                visibility: SpaceLoopVisibilityFilter
            ): SpaceLoop[] => filterSpaceLoops(loops ?? [], search, hidePaused, visibility),
        ],
        activeCount: [
            (s) => [s.loops],
            (loops: SpaceLoop[] | null): number => (loops ?? []).filter((loop) => loop.enabled).length,
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadLoopsSuccess: ({ loops }) => {
            if (loops) {
                // pinned: analytics event name, renaming breaks dashboards
                posthog.capture('space loops viewed', { loop_count: loops.length })
            }
        },
        setLoopEnabled: async ({ loopId, enabled }) => {
            const saved = values.backend ? await saveSpaceLoopEnabled(values.backend, loopId, enabled, 'list') : false
            if (saved) {
                actions.loopEnabledSaved(loopId, enabled)
            } else {
                actions.loopEnabledSaveFailed(loopId)
            }
        },
        applyTemplate: ({ template }) => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('space loop template picked', { template: template.id })
            router.actions.push(urls.taskSpaceLoopNew(props.id), { template: template.id })
        },
        submitBuilder: () => {
            const request = values.builderDraft.trim()
            if (!request || values.limitReason) {
                return
            }
            const space = { id: props.id, name: values.space ? spaceLabel(values.space) : props.id }
            // The space composer starts the session, so the builder hands it the prompt and opens the Activity tab.
            actions.setSeed({
                prompt: spaceLoopBuilderPrompt(space, values.backend?.workflowBacked ?? false, request),
                autoSubmit: true,
            })
            actions.setBuilderDraft('')
            router.actions.push(urls.taskSpace(props.id))
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('space loop builder started', { loop_count: values.loops?.length ?? null })
        },
    })),
    subscriptions(({ actions }) => ({
        loadKey: (loadKey: string | null, previousKey: string | null | undefined) => {
            if (!loadKey) {
                return
            }
            if (previousKey) {
                actions.backendChanged()
            }
            actions.loadLoops()
        },
    })),
])
