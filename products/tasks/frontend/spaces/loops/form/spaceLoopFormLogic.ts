export const spaceLoopFormLogic = kea<spaceLoopFormLogicType>([
    path((key) => ['products', 'tasks', 'spaces', 'loops', 'form', 'spaceLoopFormLogic', key]),
    props({} as SpaceLoopFormLogicProps),
    key((props) => `${props.id}/${props.loopId ?? 'new'}`),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], teamLogic, ['currentTeamId'], todaySpacesLogic, ['spaceNames']],
    })),
    actions({
        initialize: (values: LoopFormValues) => ({ values }),
        patch: (patch: Partial<LoopFormValues>) => ({ patch }),
        submit: true,
        submitFinished: true,
        cancel: true,
        setDiscardOpen: (open: boolean) => ({ open }),
        leave: true,
    }),
    loaders(({ props, values }) => ({
        source: [
            null as SpaceLoopFormSource | null,
            {
                loadSource: async () => {
                    if (!values.backend || !props.loopId) {
                        throw new Error('No loop to edit')
                    }
                    return await loadSpaceLoopFormSource(values.backend, props.loopId)
                },
            },
        ],
        sandboxEnvironments: [
            [] as SandboxEnvironmentDTOApi[],
            {
                loadSandboxEnvironments: async () =>
                    values.backend && !values.backend.workflowBacked
                        ? await listSandboxEnvironments(values.backend.projectId)
                        : [],
            },
        ],
        limitReason: [
            null as string | null,
            {
                // Workflows cap runs instead of loops, so only a new loops API loop checks the project's loop cap.
                loadLimitReason: async () => {
                    if (!values.backend || values.backend.workflowBacked || props.loopId) {
                        return null
                    }
                    const page = await loopsList(values.backend.projectId, { limit: 1 })
                    const max = page.max_loops_per_team
                    const used = page.total_loop_count
                    return max !== undefined && used !== undefined && used >= max
                        ? `This project reached its limit of ${max} loops. Delete one to add another.`
                        : null
                },
            },
        ],
        spaceCanvases: [
            [] as CanvasApi[],
            {
                loadSpaceCanvases: async (spaceId: string) => {
                    if (!values.backend) {
                        return []
                    }
                    const page = await canvasesList(values.backend.projectId, { channel: spaceId, limit: 100 })
                    return page.results
                },
            },
        ],
    })),
    reducers({
        values: [
            emptyLoopFormValues(),
            {
                initialize: (_, { values }) => values,
                patch: (state, { patch }) => ({ ...state, ...patch }),
            },
        ],
        baseline: [null as string | null, { initialize: (_, { values }) => serialize(values) }],
        sourceUnavailable: [false, { loadSource: () => false, loadSourceFailure: () => true }],
        sourceMissing: [
            false,
            {
                loadSource: () => false,
                loadSourceFailure: (_, { errorObject }) => errorObject?.status === 404,
            },
        ],
        submitting: [false, { submit: () => true, submitFinished: () => false }],
        discardOpen: [false, { setDiscardOpen: (_, { open }) => open, leave: () => false }],
        canvasesSpaceId: [null as string | null, { loadSpaceCanvases: (_, spaceId) => spaceId }],
    }),
    selectors({
        backend: [
            (s) => [s.featureFlags, s.currentTeamId],
            (featureFlags: FeatureFlagsSet, currentTeamId: number | null): SpaceLoopsBackend | null =>
                spaceLoopsBackend(featureFlags, currentTeamId),
        ],
        formBackend: [
            (s) => [s.backend],
            (backend: SpaceLoopsBackend | null): LoopFormBackend => (backend?.workflowBacked ? 'workflow' : 'loops'),
        ],
        // Loading waits for the team and the loops flag, and starts again when the loop backend changes.
        loadKey: [
            (s) => [s.backend, s.featureFlags],
            (backend: SpaceLoopsBackend | null, featureFlags: FeatureFlagsSet): string | null =>
                backend && featureFlags[FEATURE_FLAGS.LOOPS] ? `${backend.projectId}:${backend.workflowBacked}` : null,
        ],
        isEdit: [() => [(_, props) => props], (props: SpaceLoopFormLogicProps): boolean => !!props.loopId],
        ready: [
            (s) => [s.baseline, s.isEdit, s.source],
            (baseline: string | null, isEdit: boolean, source: SpaceLoopFormSource | null): boolean =>
                baseline !== null && (!isEdit || !!source),
        ],
        isDirty: [
            (s) => [s.values, s.baseline],
            (values: LoopFormValues, baseline: string | null): boolean =>
                baseline !== null && serialize(values) !== baseline,
        ],
        /** Changed in the workflow editor. A save from the form would drop that work. */
        foreign: [(s) => [s.source], (source: SpaceLoopFormSource | null): boolean => !!source?.foreign],
        submitDisabledReason: [
            (s) => [s.values, s.formBackend, s.ready, s.foreign, s.limitReason, s.submitting],
            (
                values: LoopFormValues,
                formBackend: LoopFormBackend,
                ready: boolean,
                foreign: boolean,
                limitReason: string | null,
                submitting: boolean
            ): string | null => {
                if (!ready) {
                    return 'The loop is still loading.'
                }
                if (foreign) {
                    return 'This loop was changed in the workflow editor. Change it in Workflows.'
                }
                if (submitting) {
                    return 'Saving…'
                }
                return limitReason ?? loopFormInvalidReason(values, formBackend)
            },
        ],
        breadcrumbs: [
            (s) => [s.spaceNames, s.values, s.isEdit, (_, props) => props],
            (
                spaceNames: Record<string, string>,
                values: LoopFormValues,
                isEdit: boolean,
                props: SpaceLoopFormLogicProps
            ): Breadcrumb[] => [
                {
                    key: [Scene.TaskSpace, props.id],
                    name: spaceNames[props.id] ?? 'Space',
                    path: urls.taskSpace(props.id),
                    iconType: 'task',
                },
                { key: [Scene.TaskSpace, `${props.id}/loops`], name: 'Loops', path: urls.taskSpaceLoops(props.id) },
                {
                    key: [Scene.TaskSpaceLoopForm, props.loopId ?? 'new'],
                    name: isEdit ? `Edit ${values.name || 'loop'}` : 'New loop',
                },
            ],
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadSourceSuccess: ({ source }) => {
            // A reload after a partial save refreshes what the next save is based on, and keeps the person's edits.
            if (source && values.baseline === null) {
                actions.initialize(normalizeLoopFormValues(source.values))
            }
            const spaceId = (values.baseline === null ? source?.values : values.values)?.contextTarget?.spaceId
            if (spaceId) {
                actions.loadSpaceCanvases(spaceId)
            }
        },
        patch: ({ patch }) => {
            if (patch.contextTarget && patch.contextTarget.spaceId !== values.canvasesSpaceId) {
                actions.loadSpaceCanvases(patch.contextTarget.spaceId)
            }
        },
        submit: async () => {
            const backend = values.backend
            const invalidReason = values.limitReason ?? loopFormInvalidReason(values.values, values.formBackend)
            if (!backend || !values.ready || values.foreign || invalidReason) {
                actions.submitFinished()
                return
            }
            // A space name loads after the form opens, so fill it in now if the form started without it.
            const target = values.values.contextTarget
            const formValues =
                target && !target.name
                    ? { ...values.values, contextTarget: { ...target, name: values.spaceNames[target.spaceId] ?? '' } }
                    : values.values
            try {
                const loopId = await saveSpaceLoop(backend, formValues, values.source)
                // pinned: analytics event name, renaming breaks dashboards
                posthog.capture('space loop saved', {
                    action: values.isEdit ? 'updated' : 'created',
                    workflow_backed: backend.workflowBacked,
                    trigger_types: formValues.triggers.map((trigger) => trigger.type),
                })
                toast.success({ title: values.isEdit ? 'Loop saved' : 'Loop created' })
                actions.initialize(formValues)
                actions.submitFinished()
                router.actions.push(urls.taskSpaceLoop(formValues.contextTarget?.spaceId ?? props.id, loopId))
                return
            } catch (error) {
                if (error instanceof LoopScheduleSaveError) {
                    toast.error({
                        title: 'The loop saved, but its schedule did not update',
                        description: `${readableErrorMessage(error.cause) ?? ''} Save again to retry.`.trim(),
                    })
                    actions.loadSource()
                } else if ((error as { status?: number }).status === 409) {
                    toast.error({
                        title: 'This loop changed somewhere else',
                        description: 'Reload the page to see the latest version, then make your changes again.',
                    })
                } else {
                    toast.error({
                        title: values.isEdit ? 'Couldn’t save the loop' : 'Couldn’t create the loop',
                        description: readableErrorMessage(error) ?? 'Try again.',
                    })
                }
            }
            actions.submitFinished()
        },
        cancel: () => {
            if (values.isDirty) {
                actions.setDiscardOpen(true)
                return
            }
            actions.leave()
        },
        leave: () => {
            router.actions.push(
                props.loopId ? urls.taskSpaceLoop(props.id, props.loopId) : urls.taskSpaceLoops(props.id)
            )
        },
    })),
    subscriptions(({ actions, props, values }) => ({
        loadKey: (loadKey: string | null) => {
            if (!loadKey) {
                return
            }
            actions.loadSandboxEnvironments()
            actions.loadLimitReason()
            if (props.loopId) {
                actions.loadSource()
                return
            }
            const templateId = router.values.searchParams.template
            const template = SPACE_LOOP_TEMPLATES.find((candidate) => candidate.id === templateId)
            actions.initialize(
                normalizeLoopFormValues({
                    ...emptyLoopFormValues(),
                    ...(template ? spaceLoopTemplateFormValues(template) : {}),
                    contextTarget: {
                        spaceId: props.id,
                        name: values.spaceNames[props.id] ?? '',
                        outputs: defaultLoopContextOutputs(),
                    },
                })
            )
            actions.loadSpaceCanvases(props.id)
        },
    })),
])
