export const newSessionSceneLogic = kea<newSessionSceneLogicType>([
    path(['products', 'tasks', 'spaces', 'newSessionSceneLogic']),
    connect(() => ({
        values: [todaySpacesLogic, ['sortedSpaces', 'spacesLoading', 'spacesUnavailable', 'lastSpaceId']],
        actions: [todaySpacesLogic, ['loadSpaces']],
    })),
    actions({
        pickSpace: (spaceId: string) => ({ spaceId }),
        setRouteSpaceId: (spaceId: string | null) => ({ spaceId }),
        sessionStarted: (sessionId: string) => ({ sessionId }),
    }),
    reducers({
        routeSpaceId: [null as string | null, { setRouteSpaceId: (_, { spaceId }) => spaceId }],
    }),
    selectors({
        spaceChoice: [
            (s) => [s.sortedSpaces, s.routeSpaceId, s.lastSpaceId],
            (
                sortedSpaces: ChannelDTOApi[],
                routeSpaceId: string | null,
                lastSpaceId: string | null
            ): NewSessionSpaceChoice => newSessionSpace(sortedSpaces, routeSpaceId, lastSpaceId),
        ],
        space: [
            (s) => [s.spaceChoice],
            (spaceChoice: NewSessionSpaceChoice): ChannelDTOApi | null => spaceChoice.space,
        ],
        spaceGroups: [
            (s) => [s.sortedSpaces],
            (sortedSpaces: ChannelDTOApi[]): NewSessionSpaceGroup[] => newSessionSpaceGroups(sortedSpaces),
        ],
        composerRepositoryConfig: [
            (s) => [s.space],
            (space: ChannelDTOApi | null): SpaceComposerRepositoryConfig => spaceComposerRepositoryConfig(space),
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                { key: Scene.TaskSpaces, name: 'Spaces', path: urls.taskSpaces(), iconType: 'task' },
                { key: Scene.TaskNewSession, name: 'New session', path: urls.taskNewSession(), iconType: 'task' },
            ],
        ],
    }),
    listeners(({ values }) => ({
        // Like PostHog Desktop, a pick moves to that space's own New session, so it becomes the last space too.
        pickSpace: ({ spaceId }) => {
            router.actions.push(urls.taskSpaceNewSession(spaceId))
        },
        sessionStarted: ({ sessionId }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('today new session started', {
                space_role: values.space?.system_role ?? null,
                space_source: values.spaceChoice.source,
            })
            router.actions.push(urls.aiTask(sessionId))
        },
    })),
    urlToAction(({ actions }) => ({
        [urls.taskNewSession()]: () => actions.setRouteSpaceId(null),
        [urls.taskSpaceNewSession(':id')]: ({ id }) => actions.setRouteSpaceId(id ?? null),
    })),
])
