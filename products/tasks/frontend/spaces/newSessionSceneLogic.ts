/** The `{ value, items }` shape is what the combobox reads as a group. */
export interface NewSessionSpaceGroup {
    value: string
    items: string[]
}

/** `route` is a space's own New session, or a pick in the heading. `last_used` and `personal` are the generic default. */
export type NewSessionSpaceSource = 'route' | 'last_used' | 'personal' | 'first'

export interface NewSessionSpaceChoice {
    space: ChannelDTOApi | null
    source: NewSessionSpaceSource | null
}

/** Like PostHog Desktop: the space in the URL, else the last space the person was in, else their personal space. */
export function newSessionSpace(
    spaces: ChannelDTOApi[],
    routeSpaceId: string | null,
    lastSpaceId: string | null
): NewSessionSpaceChoice {
    const candidates: [NewSessionSpaceSource, ChannelDTOApi | undefined][] = [
        ['route', spaces.find((space) => space.id === routeSpaceId)],
        ['last_used', spaces.find((space) => space.id === lastSpaceId)],
        ['personal', spaces.find((space) => space.system_role === 'personal')],
        ['first', spaces[0]],
    ]
    const [source, space] = candidates.find(([, candidate]) => candidate) ?? [null, null]
    return { space: space ?? null, source }
}

/** The personal and starred spaces first, then the rest, under the same headings as the Spaces page. */
export function newSessionSpaceGroups(spaces: ChannelDTOApi[]): NewSessionSpaceGroup[] {
    const starredIds = starredSpaces(spaces).map((space) => space.id)
    const restIds = spaces.filter((space) => !starredIds.includes(space.id)).map((space) => space.id)
    return [
        { value: 'Starred', items: starredIds },
        { value: 'Spaces', items: restIds },
    ].filter((group) => group.items.length > 0)
}

