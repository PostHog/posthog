export const newSessionSceneLogic = kea<newSessionSceneLogicType>([
    path(['products', 'tasks', 'spaces', 'newSessionSceneLogic']),
    connect(() => ({
        values: [
            todaySpacesLogic,
            ['sortedSpaces', 'spacesLoading', 'spacesUnavailable', 'lastSpaceId'],
            aiConsentLogic,
            ['dataProcessingAccepted'],
        ],
        actions: [todaySpacesLogic, ['loadSpaces', 'loadSpacesSuccess', 'loadRecentTasks']],
    })),
    actions({
        pickSpace: (spaceId: string) => ({ spaceId }),
        setRouteSpaceId: (spaceId: string | null) => ({ spaceId }),
        setPendingAsk: (ask: string | null) => ({ ask }),
        seedPendingAsk: true,
        sessionStarted: (sessionId: string) => ({ sessionId }),
    }),
    reducers({
        routeSpaceId: [null as string | null, { setRouteSpaceId: (_, { spaceId }) => spaceId }],
        // A question from `?ask=` that waits for the spaces to load, so it can go to the chosen space's composer.
        pendingAsk: [null as string | null, { setPendingAsk: (_, { ask }) => ask }],
    }),
    selectors({
        spaceChoice: [
            (s) => [s.sortedSpaces, s.routeSpaceId, s.lastSpaceId],
            (
                sortedSpaces: ChannelDTOApi[],
                routeSpaceId: string | null,
                lastSpaceId: string | null
            ): NewSessionSpaceChoice => newSessionSpace(sortedSpaces, routeSpaceId, lastSpaceId),
        ],
        space: [
            (s) => [s.spaceChoice],
            (spaceChoice: NewSessionSpaceChoice): ChannelDTOApi | null => spaceChoice.space,
        ],
        spaceGroups: [
            (s) => [s.sortedSpaces],
            (sortedSpaces: ChannelDTOApi[]): NewSessionSpaceGroup[] => newSessionSpaceGroups(sortedSpaces),
        ],
        composerRepositoryConfig: [
            (s) => [s.space],
            (space: ChannelDTOApi | null): SpaceComposerRepositoryConfig => spaceComposerRepositoryConfig(space),
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                { key: Scene.TaskSpaces, name: 'Spaces', path: urls.taskSpaces(), iconType: 'task' },
                { key: Scene.TaskNewSession, name: 'New session', path: urls.taskNewSession(), iconType: 'task' },
            ],
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        // Like PostHog Desktop, a pick moves to that space's own New session, so it becomes the last space too.
        pickSpace: ({ spaceId }) => {
            router.actions.push(urls.taskSpaceNewSession(spaceId))
        },
        setPendingAsk: () => actions.seedPendingAsk(),
        loadSpacesSuccess: () => actions.seedPendingAsk(),
        seedPendingAsk: () => {
            const { pendingAsk, space } = values
            if (!pendingAsk || !space) {
                return
            }
            actions.setPendingAsk(null)
            const seedLogic = composerSeedLogic({ panelId: newSessionComposerPanelId(space.id) })
            // A keyed logic keeps its state only while it is mounted, so this mount holds the seed until the composer
            // mounts and takes it.
            cache.disposables.add(() => seedLogic.mount(), 'askSeed', { pauseOnPageHidden: false })
            // `ask` comes from the URL. Like `/ai?ask=`, it only fills the composer until the organization accepts
            // AI data processing.
            seedLogic.actions.setSeed({ prompt: pendingAsk, autoSubmit: values.dataProcessingAccepted })
        },
        sessionStarted: ({ sessionId }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('today new session started', {
                space_role: values.space?.system_role ?? null,
                space_source: values.spaceChoice.source,
            })
            actions.loadRecentTasks()
            router.actions.push(urls.aiTask(sessionId))
        },
    })),
    urlToAction(({ actions }) => {
        const takeAsk = (search: Record<string, any>, hash: Record<string, any>): void => {
            if (search.ask) {
                const { ask, ...remainingSearch } = search
                // Remove the question first, so a later visit to this URL cannot send it again.
                router.actions.replace(router.values.location.pathname, remainingSearch, hash)
                actions.setPendingAsk(String(ask))
            }
        }
        return {
            [urls.taskNewSession()]: (_, search, hash) => {
                actions.setRouteSpaceId(null)
                takeAsk(search, hash)
            },
            [urls.taskSpaceNewSession(':id')]: ({ id }, search, hash) => {
                actions.setRouteSpaceId(id ?? null)
                takeAsk(search, hash)
            },
        }
    }),
])
