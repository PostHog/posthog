import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import { router, urlToAction } from 'kea-router'
import posthog from 'posthog-js'

import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { todaySpacesLogic } from '~/layout/today/todaySpacesLogic'
import { Breadcrumb } from '~/types'

import { ChannelDTOApi } from '../generated/api.schemas'
import { SpaceComposerRepositoryConfig, spaceComposerRepositoryConfig } from './spaceSceneLogic'

// pinned: `space_source` value of the new session event
export type NewSessionSpaceSource = 'personal'

export interface NewSessionSpaceChoice {
    space: ChannelDTOApi | null
    source: NewSessionSpaceSource | null
}

/** A new chat always starts in the personal space, so only its author can see it. */
export function newSessionSpace(spaces: ChannelDTOApi[]): NewSessionSpaceChoice {
    const space = spaces.find((candidate) => candidate.system_role === 'personal') ?? null
    return { space, source: space ? 'personal' : null }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newSessionSceneLogicValues {
    sortedSpaces: ChannelDTOApi[] // todaySpacesLogic
    spacesLoading: boolean // todaySpacesLogic
    spacesUnavailable: boolean // todaySpacesLogic
    breadcrumbs: Breadcrumb[]
    composerRepositoryConfig: SpaceComposerRepositoryConfig
    space: ChannelDTOApi | null
    spaceChoice: NewSessionSpaceChoice
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newSessionSceneLogicActions {
    loadSpaces: () => any // todaySpacesLogic
    sessionStarted: (sessionId: string) => {
        sessionId: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newSessionSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        spaceChoice: (sortedSpaces: ChannelDTOApi[]) => NewSessionSpaceChoice
        space: (spaceChoice: NewSessionSpaceChoice) => ChannelDTOApi | null
        composerRepositoryConfig: (space: ChannelDTOApi | null) => SpaceComposerRepositoryConfig
    }
}

export type newSessionSceneLogicType = MakeLogicType<
    newSessionSceneLogicValues,
    newSessionSceneLogicActions,
    Record<string, any>,
    newSessionSceneLogicMeta
>

export const newSessionSceneLogic = kea<newSessionSceneLogicType>([
    path(['products', 'tasks', 'spaces', 'newSessionSceneLogic']),
    connect(() => ({
        values: [todaySpacesLogic, ['sortedSpaces', 'spacesLoading', 'spacesUnavailable']],
        actions: [todaySpacesLogic, ['loadSpaces']],
    })),
    actions({
        sessionStarted: (sessionId: string) => ({ sessionId }),
    }),
    selectors({
        spaceChoice: [
            (s) => [s.sortedSpaces],
            (sortedSpaces: ChannelDTOApi[]): NewSessionSpaceChoice => newSessionSpace(sortedSpaces),
        ],
        space: [
            (s) => [s.spaceChoice],
            (spaceChoice: NewSessionSpaceChoice): ChannelDTOApi | null => spaceChoice.space,
        ],
        composerRepositoryConfig: [
            (s) => [s.space],
            (space: ChannelDTOApi | null): SpaceComposerRepositoryConfig => spaceComposerRepositoryConfig(space),
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                { key: Scene.TaskNewSession, name: 'New chat', path: urls.taskNewSession(), iconType: 'task' },
            ],
        ],
    }),
    listeners(({ values }) => ({
        sessionStarted: ({ sessionId }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('today new session started', {
                space_role: values.space?.system_role ?? null,
                space_source: values.spaceChoice.source,
            })
            router.actions.push(urls.aiTask(sessionId))
        },
    })),
    urlToAction(() => ({
        // The old per-space link still opens, but the chat starts personal like every other.
        [urls.taskSpaceNewSession(':id')]: () => router.actions.replace(urls.taskNewSession()),
    })),
])
