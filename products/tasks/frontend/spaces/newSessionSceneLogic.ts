import { router } from 'kea-router'
import posthog from 'posthog-js'

import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { starredSpaces, todaySpacesLogic } from '~/layout/today/todaySpacesLogic'
import { Breadcrumb } from '~/types'

import { ChannelDTOApi } from '../generated/api.schemas'
import { SpaceComposerRepositoryConfig, spaceComposerRepositoryConfig } from './spaceSceneLogic'

/** The `{ value, items }` shape is what the combobox reads as a group. */
export interface NewSessionSpaceGroup {
    value: string
    items: string[]
}

/** Like PostHog Desktop: a new session files into the personal space until the user picks another one. */
export function newSessionSpace(spaces: ChannelDTOApi[], pickedSpaceId: string | null): ChannelDTOApi | null {
    return (
        spaces.find((space) => space.id === pickedSpaceId) ??
        spaces.find((space) => space.system_role === 'personal') ??
        spaces[0] ??
        null
    )
}

/** The personal and starred spaces first, then the rest, under the same headings as the Spaces page. */
export function newSessionSpaceGroups(spaces: ChannelDTOApi[]): NewSessionSpaceGroup[] {
    const starredIds = starredSpaces(spaces).map((space) => space.id)
    const restIds = spaces.filter((space) => !starredIds.includes(space.id)).map((space) => space.id)
    return [
        { value: 'Starred', items: starredIds },
        { value: 'Spaces', items: restIds },
    ].filter((group) => group.items.length > 0)
}

