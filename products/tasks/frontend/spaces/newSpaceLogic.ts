export type newSpaceLogicType = MakeLogicType<
    newSpaceLogicValues,
    newSpaceLogicActions,
    Record<string, any>,
    newSpaceLogicMeta
>

export const newSpaceLogic = kea<newSpaceLogicType>([
    path(['products', 'tasks', 'spaces', 'newSpaceLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], todaySpacesLogic, ['spaces']],
        actions: [todaySpacesLogic, ['loadSpaces']],
    })),
    actions({
        openNewSpace: true,
        closeNewSpace: true,
        setName: (name: string) => ({ name }),
        submitNewSpace: true,
        createSpace: (name: string) => ({ name }),
        createSpaceSuccess: (space: ChannelDTOApi) => ({ space }),
        createSpaceFailure: true,
    }),
    reducers({
        isOpen: [
            false,
            {
                openNewSpace: () => true,
                closeNewSpace: () => false,
                createSpaceSuccess: () => false,
            },
        ],
        name: ['', { openNewSpace: () => '', setName: (_, { name }) => normalizeSpaceNameInput(name) }],
        submitAttempted: [false, { openNewSpace: () => false, submitNewSpace: () => true }],
        submitting: [
            false,
            {
                createSpace: () => true,
                createSpaceSuccess: () => false,
                createSpaceFailure: () => false,
            },
        ],
    }),
    selectors({
        normalizedName: [(s) => [s.name], (name: string): string => normalizeSpaceName(name)],
        nameError: [
            (s) => [s.normalizedName, s.spaces, s.submitAttempted],
            (normalizedName: string, spaces: ChannelDTOApi[], submitAttempted: boolean): string | null =>
                normalizedName
                    ? spaceNameError(normalizedName, spaces)
                    : submitAttempted
                      ? 'Enter a name for the space.'
                      : null,
        ],
    }),
    listeners(({ actions, values }) => ({
        submitNewSpace: () => {
            if (values.submitting || !values.normalizedName || values.nameError) {
                return
            }
            actions.createSpace(values.normalizedName)
        },
        createSpace: async ({ name }) => {
            const projectId = String(values.currentTeamId)
            let space: ChannelDTOApi
            try {
                space = await taskChannelsCreate(projectId, { name, channel_type: 'public', star: true })
            } catch {
                toast.error({ title: 'Couldn’t create the space. Try again.' })
                actions.createSpaceFailure()
                return
            }
            if (!space.starred) {
                try {
                    // Create returns an existing public space with that name unchanged, so star it here to match what the user asked for.
                    await taskChannelsStarCreate(projectId, space.id, { starred: true })
                    space = { ...space, starred: true }
                } catch {
                    // The space exists either way, and starring it later is one click.
                }
            }
            actions.createSpaceSuccess(space)
        },
        createSpaceSuccess: ({ space }) => {
            actions.loadSpaces()
            router.actions.push(urls.taskSpace(space.id))
        },
    })),
])
