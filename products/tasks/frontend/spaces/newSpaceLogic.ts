import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'

import { toast } from '@posthog/quill'

import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { todaySpacesLogic } from '~/layout/today/todaySpacesLogic'

import { taskChannelsCreate, taskChannelsStarCreate } from '../generated/api'
import { ChannelDTOApi } from '../generated/api.schemas'

export const NEW_SPACE_NAME_MAX_LENGTH = 80

// The server stores names as lowercase letters, numbers, and hyphens, so the field shows that shape as the user types.
export function normalizeSpaceNameInput(name: string): string {
    return name
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+/, '')
}

export function normalizeSpaceName(name: string): string {
    return normalizeSpaceNameInput(name).replace(/-+$/, '')
}

export function spaceNameError(name: string, spaces: Pick<ChannelDTOApi, 'name'>[]): string | null {
    if (name === 'me' || name === 'personal') {
        return `"${name}" is reserved for your personal space.`
    }
    if (name === 'general') {
        return `"${name}" is reserved for your team's shared space.`
    }
    if (spaces.some((space) => space.name === name)) {
        return `#${name} already exists. Try another name.`
    }
    return null
}

