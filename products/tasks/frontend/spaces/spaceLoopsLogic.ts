import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic, FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { spaceLabel } from '~/layout/today/todaySpacesLogic'

import { hogFlowsList } from 'products/workflows/frontend/generated/api'

import { loopsList } from '../generated/api'
import { ChannelDTOApi } from '../generated/api.schemas'
import { SpaceLoop, spaceLoopBuilderPrompt, spaceLoopsFromHogFlows, spaceLoopsFromLoops } from './spaceLoops'
import { SpaceSceneLogicProps, spaceSceneLogic } from './spaceSceneLogic'

// PostHog Desktop reads the same page size, so both apps show the same loops.
const LOOPS_LIST_LIMIT = 100

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface spaceLoopsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    space: ChannelDTOApi | null // spaceSceneLogic
    currentTeamId: number | null // teamLogic
    loops: SpaceLoop[] | null
    loopsLoading: boolean
    loopsUnavailable: boolean
    workflowBacked: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface spaceLoopsLogicActions {
    applySuggestion: (prompt: string) => {
        prompt: string
    } // spaceSceneLogic
    loadLoops: () => any
    loadLoopsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadLoopsSuccess: (
        loops: SpaceLoop[] | null,
        payload?: any
    ) => {
        loops: SpaceLoop[] | null
        payload?: any
    }
    startLoopBuilder: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface spaceLoopsLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        workflowBacked: (featureFlags: FeatureFlagsSet) => boolean
    }
}

export type spaceLoopsLogicType = MakeLogicType<
    spaceLoopsLogicValues,
    spaceLoopsLogicActions,
    SpaceSceneLogicProps,
    spaceLoopsLogicMeta
>

export const spaceLoopsLogic = kea<spaceLoopsLogicType>([
    path((id) => ['products', 'tasks', 'spaces', 'spaceLoopsLogic', id]),
    props({} as SpaceSceneLogicProps),
    key((props) => props.id),
    connect((props: SpaceSceneLogicProps) => ({
        values: [featureFlagLogic, ['featureFlags'], spaceSceneLogic(props), ['space'], teamLogic, ['currentTeamId']],
        actions: [spaceSceneLogic(props), ['applySuggestion']],
    })),
    actions({
        startLoopBuilder: true,
    }),
    loaders(({ props, values }) => ({
        loops: [
            null as SpaceLoop[] | null,
            {
                loadLoops: async () => {
                    if (!values.currentTeamId) {
                        return null
                    }
                    const projectId = String(values.currentTeamId)
                    if (values.workflowBacked) {
                        const page = await hogFlowsList(projectId, { origin_product: 'loops', limit: LOOPS_LIST_LIMIT })
                        return spaceLoopsFromHogFlows(page.results, props.id)
                    }
                    const page = await loopsList(projectId, { limit: LOOPS_LIST_LIMIT })
                    return spaceLoopsFromLoops(page.results, props.id)
                },
            },
        ],
    })),
    reducers({
        loopsUnavailable: [false, { loadLoops: () => false, loadLoopsFailure: () => true }],
    }),
    selectors({
        workflowBacked: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.LOOPS_HOG_FLOWS],
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadLoopsSuccess: ({ loops }) => {
            if (loops) {
                // pinned: analytics event name, renaming breaks dashboards
                posthog.capture('space loops viewed', { loop_count: loops.length })
            }
        },
        startLoopBuilder: () => {
            const space = { id: props.id, name: values.space ? spaceLabel(values.space) : props.id }
            // The composer lives on the Activity tab, so go there before the seed lands.
            router.actions.push(urls.taskSpace(props.id))
            actions.applySuggestion(spaceLoopBuilderPrompt(space, values.workflowBacked))
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('space loop builder started', { loop_count: values.loops?.length ?? null })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadLoops()
    }),
])
