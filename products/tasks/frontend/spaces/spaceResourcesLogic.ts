export const spaceResourcesLogic: LogicWrapper<spaceResourcesLogicType> = kea<spaceResourcesLogicType>([
    path(['products', 'tasks', 'frontend', 'spaces', 'spaceResourcesLogic']),
    props({} as SpaceResourcesProps),
    key((props) => props.id),
    connect({ values: [teamLogic, ['currentTeamId']] }),
    actions({
        setQuery: (query: string) => ({ query }),
        setPickerOpen: (open: boolean) => ({ open }),
        addFile: (fileId: string) => ({ fileId }),
        removeFile: (fileId: string) => ({ fileId }),
        togglePinned: (fileId: string) => ({ fileId }),
        featureCanvas: (canvasId: string | null) => ({ canvasId }),
    }),
    reducers({
        query: ['', { setQuery: (_, { query }) => query }],
        pickerOpen: [false, { setPickerOpen: (_, { open }) => open }],
        configUnavailable: [false, { loadConfigSuccess: () => false, loadConfigFailure: () => true }],
        filesUnavailable: [false, { loadFilesSuccess: () => false, loadFilesFailure: () => true }],
    }),
    loaders(({ values, props }) => ({
        config: [
            null as SpaceResourceConfigApi | null,
            {
                loadConfig: async () => taskChannelsResourcesRetrieve(String(values.currentTeamId), props.id),
                saveConfig: async (config: SpaceResourceConfigApi) => {
                    try {
                        return await taskChannelsResourcesUpdate(String(values.currentTeamId), props.id, config)
                    } catch (error) {
                        toast.error({ title: 'Couldn’t save this space. Try again.' })
                        throw error
                    }
                },
            },
        ],
        files: [
            [] as FileSystemApi[],
            {
                loadFiles: async () => {
                    const files: FileSystemApi[] = []
                    let next = true
                    while (next) {
                        const page = await fileSystemList(String(values.currentTeamId), {
                            limit: 200,
                            offset: files.length,
                        })
                        files.push(...page.results)
                        next = !!page.next && page.results.length > 0
                    }
                    return files
                        .filter(
                            (file) =>
                                ['dashboard', 'insight', 'notebook', 'folder'].includes(file.type ?? '') &&
                                file.user_access_level !== 'none'
                        )
                        .map((file) => ({
                            ...file,
                            href: file.type === 'folder' ? urls.reports(file.path) : file.href,
                        }))
                },
            },
        ],
    })),
    selectors({
        fileById: [
            (s) => [s.files],
            (files: FileSystemApi[]): Record<string, FileSystemApi> =>
                Object.fromEntries(files.map((file) => [file.id, file])),
        ],
        availableFiles: [
            (s) => [s.files, s.config, s.query],
            (files: FileSystemApi[], config: SpaceResourceConfigApi | null, query: string): FileSystemApi[] => {
                const added = new Set(config?.resources.map((item) => item.file_id))
                return files.filter(
                    (file) => !added.has(file.id) && file.path.toLowerCase().includes(query.toLowerCase())
                )
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        addFile: ({ fileId }) => {
            if (!values.config || values.configLoading) {
                return
            }
            actions.saveConfig({
                ...values.config,
                resources: [...values.config.resources, { file_id: fileId, pinned: false }],
            })
        },
        removeFile: ({ fileId }) => {
            if (!values.config || values.configLoading) {
                return
            }
            actions.saveConfig({
                ...values.config,
                resources: values.config.resources.filter((item) => item.file_id !== fileId),
            })
        },
        togglePinned: ({ fileId }) => {
            if (!values.config || values.configLoading) {
                return
            }
            actions.saveConfig({
                ...values.config,
                resources: values.config.resources.map((item) =>
                    item.file_id === fileId ? { ...item, pinned: !item.pinned } : item
                ),
            })
        },
        featureCanvas: ({ canvasId }) => {
            if (!values.config || values.configLoading) {
                return
            }
            actions.saveConfig({ ...values.config, featured_canvas: canvasId })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadConfig()
        actions.loadFiles()
    }),
])
