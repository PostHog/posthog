export const AUTO_ARCHIVE_PRESET_DAYS = [1, 3, 7, 14, 30]
export const AUTO_ARCHIVE_MIN_DAYS = 1
export const AUTO_ARCHIVE_MAX_DAYS = 365

/** `null` turns auto-archive off, `'custom'` shows the number field. */
export type AutoArchiveSelection = number | null | 'custom'

export function autoArchiveDaysError(days: number | null): string | null {
    if (days === null) {
        return 'Enter a number of days'
    }
    if (!Number.isInteger(days) || days < AUTO_ARCHIVE_MIN_DAYS || days > AUTO_ARCHIVE_MAX_DAYS) {
        return `Enter a whole number from ${AUTO_ARCHIVE_MIN_DAYS} to ${AUTO_ARCHIVE_MAX_DAYS}`
    }
    return null
}

const SPACE_NAME_MAX_LENGTH = 128

export function spaceNameError(name: string): string | null {
    if (!name) {
        return 'Enter a name'
    }
    if (name.length > SPACE_NAME_MAX_LENGTH) {
        return `Use ${SPACE_NAME_MAX_LENGTH} characters or fewer`
    }
    return null
}

