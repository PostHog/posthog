import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { Scene } from 'scenes/sceneTypes'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { todaySessionMenuLogic } from '~/layout/today/todaySessionMenuLogic'
import { spaceLabel } from '~/layout/today/todaySpacesLogic'
import { TodayWorkGroup, groupByDay, sessionItem } from '~/layout/today/todayWorkItems'
import { Breadcrumb } from '~/types'

import { taskChannelsRetrieve, tasksList } from '../generated/api'
import { ChannelDTOApi, TaskListItemApi } from '../generated/api.schemas'

const SPACE_FEED_LIMIT = 50

export interface SpaceSceneLogicProps {
    id: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface spaceSceneLogicValues {
    currentTeamId: number | null // teamLogic
    breadcrumbs: Breadcrumb[]
    feedGroups: TodayWorkGroup[]
    sessions: TaskListItemApi[]
    sessionsLoading: boolean
    sessionsUnavailable: boolean
    space: ChannelDTOApi | null
    spaceLoading: boolean
    spaceUnavailable: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface spaceSceneLogicActions {
    sessionUpdated: (sessionId: string) => {
        sessionId: string
    } // todaySessionMenuLogic
    loadSessions: () => any
    loadSessionsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSessionsSuccess: (
        sessions: TaskListItemApi[],
        payload?: any
    ) => {
        sessions: TaskListItemApi[]
        payload?: any
    }
    loadSpace: () => any
    loadSpaceFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSpaceSuccess: (
        space: ChannelDTOApi | null,
        payload?: any
    ) => {
        space: ChannelDTOApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface spaceSceneLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        feedGroups: (sessions: TaskListItemApi[]) => TodayWorkGroup[]
        breadcrumbs: (space: ChannelDTOApi | null, arg: any) => Breadcrumb[]
    }
}

export type spaceSceneLogicType = MakeLogicType<
    spaceSceneLogicValues,
    spaceSceneLogicActions,
    SpaceSceneLogicProps,
    spaceSceneLogicMeta
>

export const spaceSceneLogic = kea<spaceSceneLogicType>([
    path((id) => ['products', 'tasks', 'spaces', 'spaceSceneLogic', id]),
    props({} as SpaceSceneLogicProps),
    key((props) => props.id),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [todaySessionMenuLogic, ['sessionUpdated']],
    })),
    loaders(({ props, values }) => ({
        space: [
            null as ChannelDTOApi | null,
            {
                loadSpace: async () =>
                    values.currentTeamId ? await taskChannelsRetrieve(String(values.currentTeamId), props.id) : null,
            },
        ],
        sessions: [
            [] as TaskListItemApi[],
            {
                loadSessions: async () => {
                    if (!values.currentTeamId) {
                        return []
                    }
                    const response = await tasksList(String(values.currentTeamId), {
                        channel: props.id,
                        ordering: '-last_activity_at',
                        basic: true,
                        limit: SPACE_FEED_LIMIT,
                    })
                    return response.results
                },
            },
        ],
    })),
    reducers({
        sessionsUnavailable: [false, { loadSessions: () => false, loadSessionsFailure: () => true }],
        spaceUnavailable: [false, { loadSpace: () => false, loadSpaceFailure: () => true }],
    }),
    selectors({
        feedGroups: [
            (s) => [s.sessions],
            (sessions: TaskListItemApi[]): TodayWorkGroup[] =>
                groupByDay(sessions.filter((task) => !task.archived).map(sessionItem)),
        ],
        breadcrumbs: [
            (s) => [s.space, (_, props) => props],
            (space: ChannelDTOApi | null, props: SpaceSceneLogicProps): Breadcrumb[] => [
                {
                    key: [Scene.TaskSpace, props.id],
                    name: space ? spaceLabel(space) : 'Space',
                    path: urls.taskSpace(props.id),
                    iconType: 'task',
                },
            ],
        ],
    }),
    listeners(({ actions }) => ({
        sessionUpdated: () => {
            actions.loadSessions()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSpace()
        actions.loadSessions()
    }),
])
