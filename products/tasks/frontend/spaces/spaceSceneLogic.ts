export const spaceSceneLogic = kea<spaceSceneLogicType>([
    path((id) => ['products', 'tasks', 'spaces', 'spaceSceneLogic', id]),
    props({} as SpaceSceneLogicProps),
    key((props) => props.id),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentTeamId']],
        actions: [
            todaySessionMenuLogic,
            ['sessionUpdated'],
            todaySpacesLogic,
            ['loadSpaces', 'loadSpacesSuccess', 'loadTaskActivity', 'loadPullRequestStates'],
        ],
    })),
    actions({
        updateSpace: (patch: PatchedChannelUpdateApi) => ({ patch }),
        setStarred: (starred: boolean) => ({ starred }),
        deleteSpace: true,
        spaceSaved: (space: ChannelDTOApi) => ({ space }),
        savingFinished: true,
        sessionStarted: (sessionId: string) => ({ sessionId }),
        focusComposer: true,
        setAutoArchiveSelection: (selection: AutoArchiveSelection) => ({ selection }),
        setAutoArchiveCustomDays: (days: number | null) => ({ days }),
        saveAutoArchiveCustomDays: true,
    }),
    loaders(({ props, values }) => ({
        space: [
            null as ChannelDTOApi | null,
            {
                loadSpace: async () =>
                    values.currentTeamId ? await taskChannelsRetrieve(String(values.currentTeamId), props.id) : null,
            },
        ],
        members: [
            [] as TaskUserBasicInfoApi[],
            {
                loadMembers: async () => await taskChannelsMembersRetrieve(String(values.currentTeamId), props.id),
                // The creator always stays a member, whatever the picker sends.
                setMemberIds: async (userIds: number[]) =>
                    await taskChannelsMembersUpdate(String(values.currentTeamId), props.id, {
                        user_ids: values.creatorId === null ? userIds : [...new Set([values.creatorId, ...userIds])],
                    }),
            },
        ],
        sessions: [
            [] as TaskListItemApi[],
            {
                loadSessions: async () => {
                    if (!values.currentTeamId) {
                        return []
                    }
                    const response = await tasksList(String(values.currentTeamId), {
                        channel: props.id,
                        ordering: '-last_activity_at',
                        basic: true,
                        limit: SPACE_FEED_LIMIT,
                    })
                    return response.results
                },
            },
        ],
    })),
    reducers({
        sessionsUnavailable: [false, { loadSessions: () => false, loadSessionsFailure: () => true }],
        spaceUnavailable: [false, { loadSpace: () => false, loadSpaceFailure: () => true }],
        spaceMissing: [
            false,
            {
                loadSpace: () => false,
                loadSpaceFailure: (_, { errorObject }) => errorObject?.status === 404,
            },
        ],
        space: {
            spaceSaved: (_, { space }) => space,
            setStarred: (state, { starred }) => (state ? { ...state, starred } : state),
            // The sidebar can star or unstar this space too, so follow the shared list.
            loadSpacesSuccess: (state, { spaces }) => {
                const listed = state && spaces.find((space) => space.id === state.id)
                return state && listed ? { ...state, starred: listed.starred } : state
            },
        },
        // Each request bumps the counter, so the composer focuses again even when it is already mounted.
        composerFocusRequest: [0, { focusComposer: (state) => state + 1 }],
        savingSpace: [
            false,
            {
                updateSpace: () => true,
                setStarred: () => true,
                deleteSpace: () => true,
                spaceSaved: () => false,
                savingFinished: () => false,
            },
        ],
        autoArchiveCustomOpen: [false, { setAutoArchiveSelection: (_, { selection }) => selection === 'custom' }],
        autoArchiveCustomDays: [
            null as number | null,
            {
                setAutoArchiveCustomDays: (_, { days }) => days,
                setAutoArchiveSelection: (state, { selection }) => (typeof selection === 'number' ? selection : state),
                loadSpaceSuccess: (_, { space }) => space?.auto_archive_after_days ?? null,
            },
        ],
    }),
    selectors({
        creatorId: [(s) => [s.space], (space: ChannelDTOApi | null): number | null => space?.created_by?.id ?? null],
        // A saved value outside the presets shows as custom.
        autoArchiveSelection: [
            (s) => [s.space, s.autoArchiveCustomOpen],
            (space: ChannelDTOApi | null, customOpen: boolean): AutoArchiveSelection => {
                const days = space?.auto_archive_after_days ?? null
                return customOpen || (days !== null && !AUTO_ARCHIVE_PRESET_DAYS.includes(days)) ? 'custom' : days
            },
        ],
        // Mirrors the backend rule: only project admins change auto-archive outside a personal space.
        autoArchiveDisabledReason: [
            (s) => [s.space, s.currentTeam, s.savingSpace],
            (
                space: ChannelDTOApi | null,
                currentTeam: TeamPublicType | TeamType | null,
                savingSpace: boolean
            ): string | null => {
                const level = currentTeam?.effective_membership_level ?? null
                if (
                    space?.channel_type !== 'personal' &&
                    (level === null || level < OrganizationMembershipLevel.Admin)
                ) {
                    return 'Only project admins can change auto-archive for shared spaces'
                }
                return savingSpace ? 'Saving your last change' : null
            },
        ],
        autoArchiveCustomError: [
            (s) => [s.autoArchiveCustomDays],
            (days: number | null): string | null => (days === null ? null : autoArchiveDaysError(days)),
        ],
        autoArchiveCustomSaveDisabledReason: [
            (s) => [s.autoArchiveDisabledReason, s.autoArchiveCustomDays, s.space],
            (disabledReason: string | null, days: number | null, space: ChannelDTOApi | null): string | null =>
                disabledReason ??
                autoArchiveDaysError(days) ??
                (days === space?.auto_archive_after_days ? 'Change the number of days first' : null),
        ],
        activeTab: [
            () => [router.selectors.location],
            (location: { pathname: string }): SpaceTab =>
                location.pathname.endsWith('/settings') ? 'settings' : 'feed',
        ],
        feedGroups: [
            (s) => [s.sessions],
            (sessions: TaskListItemApi[]): TodayWorkGroup[] =>
                groupByDay(sessions.filter((task) => !task.archived).map(sessionItem)),
        ],
        sessionsById: [
            (s) => [s.sessions],
            (sessions: TaskListItemApi[]): Record<string, TaskListItemApi> =>
                Object.fromEntries(sessions.map((task) => [task.id, task])),
        ],
        breadcrumbs: [
            (s) => [s.space, (_, props) => props],
            (space: ChannelDTOApi | null, props: SpaceSceneLogicProps): Breadcrumb[] => [
                {
                    key: [Scene.TaskSpace, props.id],
                    name: space ? spaceLabel(space) : 'Space',
                    path: urls.taskSpace(props.id),
                    iconType: 'task',
                },
            ],
        ],
        // The new-session composer starts on the space's first repository.
        composerRepositoryConfig: [
            (s) => [s.space],
            (space: ChannelDTOApi | null): SpaceComposerRepositoryConfig =>
                space?.repositories.length
                    ? { integrationId: space.github_integration ?? undefined, repository: space.repositories[0] }
                    : undefined,
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadSessions: () => {
            actions.loadTaskActivity()
        },
        loadSessionsSuccess: ({ sessions }) => {
            actions.loadPullRequestStates(sessionIdsWithPullRequests(sessions))
        },
        sessionUpdated: () => {
            actions.loadSessions()
        },
        setAutoArchiveSelection: ({ selection }) => {
            if (
                selection !== 'custom' &&
                !values.autoArchiveDisabledReason &&
                selection !== (values.space?.auto_archive_after_days ?? null)
            ) {
                actions.updateSpace({ auto_archive_after_days: selection })
            }
        },
        saveAutoArchiveCustomDays: () => {
            if (!values.autoArchiveCustomSaveDisabledReason) {
                actions.updateSpace({ auto_archive_after_days: values.autoArchiveCustomDays })
            }
        },
        // Open the new session like the web's new-session composer does, and list it for when the user comes back.
        sessionStarted: ({ sessionId }) => {
            actions.loadSessions()
            router.actions.push(urls.aiTask(sessionId))
        },
        loadSpaceSuccess: ({ space }) => {
            if (space?.channel_type === 'private') {
                actions.loadMembers()
            }
        },
        spaceSaved: ({ space }) => {
            if (space.channel_type === 'private') {
                actions.loadMembers()
            }
        },
        setMemberIdsFailure: ({ errorObject }) => {
            toast.error({
                title: (errorObject as { detail?: string })?.detail ?? 'Couldn’t update the members. Try again.',
            })
            actions.loadMembers()
        },
        updateSpace: async ({ patch }) => {
            try {
                actions.spaceSaved(await taskChannelsPartialUpdate(String(values.currentTeamId), props.id, patch))
                actions.loadSpaces()
            } catch (error) {
                toast.error({ title: (error as { detail?: string }).detail ?? 'Couldn’t save this change. Try again.' })
                actions.savingFinished()
            }
        },
        setStarred: async ({ starred }) => {
            try {
                await taskChannelsStarCreate(String(values.currentTeamId), props.id, { starred })
                actions.savingFinished()
                actions.loadSpaces()
            } catch {
                toast.error({ title: `Couldn’t ${starred ? 'star' : 'unstar'} this space. Try again.` })
                actions.loadSpace()
                actions.savingFinished()
            }
        },
        deleteSpace: async () => {
            try {
                await taskChannelsDestroy(String(values.currentTeamId), props.id)
                toast.success({ title: 'Space deleted' })
                actions.loadSpaces()
                router.actions.push(urls.projectHomepage())
            } catch (error) {
                toast.error({
                    title: (error as { detail?: string }).detail ?? 'Couldn’t delete this space. Try again.',
                })
                actions.savingFinished()
            }
        },
    })),
    urlToAction(({ actions, props }) => ({
        [urls.taskSpace(':id')]: ({ id }, searchParams, hashParams) => {
            if (id !== props.id || !searchParams[SPACE_COMPOSE_PARAM]) {
                return
            }
            actions.focusComposer()
            // Drop the param, so a reload or a back navigation does not focus the composer again.
            const { [SPACE_COMPOSE_PARAM]: _compose, ...rest } = searchParams
            router.actions.replace(urls.taskSpace(props.id), rest, hashParams)
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSpace()
        actions.loadSessions()
    }),
])
