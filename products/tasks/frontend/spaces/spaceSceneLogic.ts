export const spaceSceneLogic = kea<spaceSceneLogicType>([
    path((id) => ['products', 'tasks', 'spaces', 'spaceSceneLogic', id]),
    props({} as SpaceSceneLogicProps),
    key((props) => props.id),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [todaySessionMenuLogic, ['sessionUpdated'], todaySpacesLogic, ['loadSpaces']],
    })),
    actions({
        updateSpace: (patch: PatchedChannelUpdateApi) => ({ patch }),
        setStarred: (starred: boolean) => ({ starred }),
        deleteSpace: true,
        spaceSaved: (space: ChannelDTOApi) => ({ space }),
        savingFinished: true,
        setTaskDraft: (draft: string) => ({ draft }),
        createTask: true,
        createTaskSuccess: (taskId: string) => ({ taskId }),
        createTaskFailure: true,
    }),
    loaders(({ props, values }) => ({
        space: [
            null as ChannelDTOApi | null,
            {
                loadSpace: async () =>
                    values.currentTeamId ? await taskChannelsRetrieve(String(values.currentTeamId), props.id) : null,
            },
        ],
        members: [
            [] as TaskUserBasicInfoApi[],
            {
                loadMembers: async () => await taskChannelsMembersRetrieve(String(values.currentTeamId), props.id),
                setMemberIds: async (userIds: number[]) =>
                    await taskChannelsMembersUpdate(String(values.currentTeamId), props.id, { user_ids: userIds }),
            },
        ],
        sessions: [
            [] as TaskListItemApi[],
            {
                loadSessions: async () => {
                    if (!values.currentTeamId) {
                        return []
                    }
                    const response = await tasksList(String(values.currentTeamId), {
                        channel: props.id,
                        ordering: '-last_activity_at',
                        basic: true,
                        limit: SPACE_FEED_LIMIT,
                    })
                    return response.results
                },
            },
        ],
    })),
    reducers({
        sessionsUnavailable: [false, { loadSessions: () => false, loadSessionsFailure: () => true }],
        spaceUnavailable: [false, { loadSpace: () => false, loadSpaceFailure: () => true }],
        spaceMissing: [
            false,
            {
                loadSpace: () => false,
                loadSpaceFailure: (_, { errorObject }) => errorObject?.status === 404,
            },
        ],
        space: {
            spaceSaved: (_, { space }) => space,
            setStarred: (state, { starred }) => (state ? { ...state, starred } : state),
        },
        taskDraft: [
            '',
            {
                setTaskDraft: (_, { draft }) => draft,
                createTaskSuccess: () => '',
            },
        ],
        creatingTask: [
            false,
            {
                createTask: () => true,
                createTaskSuccess: () => false,
                createTaskFailure: () => false,
            },
        ],
        savingSpace: [
            false,
            {
                updateSpace: () => true,
                setStarred: () => true,
                deleteSpace: () => true,
                spaceSaved: () => false,
                savingFinished: () => false,
            },
        ],
    }),
    selectors({
        activeTab: [
            () => [router.selectors.location],
            (location: { pathname: string }): SpaceTab =>
                location.pathname.endsWith('/settings') ? 'settings' : 'feed',
        ],
        feedGroups: [
            (s) => [s.sessions],
            (sessions: TaskListItemApi[]): TodayWorkGroup[] =>
                groupByDay(sessions.filter((task) => !task.archived).map(sessionItem)),
        ],
        breadcrumbs: [
            (s) => [s.space, (_, props) => props],
            (space: ChannelDTOApi | null, props: SpaceSceneLogicProps): Breadcrumb[] => [
                {
                    key: [Scene.TaskSpace, props.id],
                    name: space ? spaceLabel(space) : 'Space',
                    path: urls.taskSpace(props.id),
                    iconType: 'task',
                },
            ],
        ],
    }),
    listeners(({ actions, props, values, cache }) => ({
        createTask: async () => {
            const prompt = values.taskDraft.trim()
            if (cache.creatingTask) {
                return
            }
            if (!prompt) {
                actions.createTaskFailure()
                return
            }
            cache.creatingTask = true
            const projectId = String(values.currentTeamId)
            const repositories = values.space?.repositories ?? []
            try {
                const task = await tasksCreate(projectId, {
                    description: prompt,
                    origin_product: TaskOriginProductEnumApi.UserCreated,
                    channel: props.id,
                    ...(repositories.length
                        ? { repositories, github_integration: values.space?.github_integration ?? null }
                        : {}),
                })
                try {
                    // No runtime, model or effort: the backend resolves them from the team and user defaults.
                    await tasksRunCreate(projectId, task.id, {
                        mode: TaskExecutionModeEnumApi.Interactive,
                        pending_user_message: prompt,
                    } as TaskRunCreateRequestSchemaApi)
                } catch (error) {
                    // A task without a run would sit in the feed and never start.
                    await tasksDestroy(projectId, task.id).catch(() => undefined)
                    throw error
                }
                actions.createTaskSuccess(task.id)
                actions.loadSessions()
                toast.success({
                    title: 'Session started',
                    action: { label: 'Open', onClick: () => router.actions.push(urls.aiTask(task.id)) },
                })
            } catch (error) {
                toast.error({ title: serverMessage(error) ?? 'Couldn’t start the session. Try again.' })
                actions.createTaskFailure()
            } finally {
                cache.creatingTask = false
            }
        },
        sessionUpdated: () => {
            actions.loadSessions()
        },
        loadSpaceSuccess: ({ space }) => {
            if (space?.channel_type === 'private') {
                actions.loadMembers()
            }
        },
        spaceSaved: ({ space }) => {
            if (space.channel_type === 'private') {
                actions.loadMembers()
            }
        },
        setMemberIdsFailure: ({ errorObject }) => {
            toast.error({
                title: (errorObject as { detail?: string })?.detail ?? 'Couldn’t update the members. Try again.',
            })
            actions.loadMembers()
        },
        updateSpace: async ({ patch }) => {
            try {
                actions.spaceSaved(await taskChannelsPartialUpdate(String(values.currentTeamId), props.id, patch))
                actions.loadSpaces()
            } catch (error) {
                toast.error({ title: (error as { detail?: string }).detail ?? 'Couldn’t save this change. Try again.' })
                actions.savingFinished()
            }
        },
        setStarred: async ({ starred }) => {
            try {
                await taskChannelsStarCreate(String(values.currentTeamId), props.id, { starred })
                actions.savingFinished()
                actions.loadSpaces()
            } catch {
                toast.error({ title: `Couldn’t ${starred ? 'star' : 'unstar'} this space. Try again.` })
                actions.loadSpace()
                actions.savingFinished()
            }
        },
        deleteSpace: async () => {
            try {
                await taskChannelsDestroy(String(values.currentTeamId), props.id)
                toast.success({ title: 'Space deleted' })
                actions.loadSpaces()
                router.actions.push(urls.projectHomepage())
            } catch (error) {
                toast.error({
                    title: (error as { detail?: string }).detail ?? 'Couldn’t delete this space. Try again.',
                })
                actions.savingFinished()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSpace()
        actions.loadSessions()
    }),
])
