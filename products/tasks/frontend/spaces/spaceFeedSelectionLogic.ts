/** The sessions picked in a space's feed for a bulk change. Separate from the sidebar's pick, which spans spaces. */
export const spaceFeedSelectionLogic: LogicWrapper<spaceFeedSelectionLogicType> = kea<spaceFeedSelectionLogicType>([
    props({} as SpaceFeedSelectionLogicProps),
    key((props) => props.id),
    path((id) => ['products', 'tasks', 'spaces', 'spaceFeedSelectionLogic', id]),
    connect((props: SpaceFeedSelectionLogicProps) => ({
        values: [spaceSceneLogic(props), ['currentTeamId', 'feedSections'], todaySpacesLogic, ['pinnedItems']],
        actions: [
            router,
            ['locationChanged'],
            spaceSceneLogic(props),
            ['loadSessions'],
            spaceFeedViewLogic,
            ['clearFilters', 'setFilters', 'setTypes', 'setView'],
            todaySpacesLogic,
            ['loadPinnedTasks', 'loadRecentTasks'],
        ],
    })),
    actions({
        setSelection: (selection: TodaySessionSelection) => ({ selection }),
        toggleSessionSelection: (sessionId: string) => ({ sessionId }),
        selectSessionRange: (sessionId: string) => ({ sessionId }),
        toggleSelectAll: true,
        clearSelection: true,
        pinSelected: true,
        fileSelectedTo: (spaceId: string) => ({ spaceId }),
        requestBulkArchive: true,
        openBulkArchiveConfirm: (count: number, running: number) => ({ count, running }),
        closeBulkArchiveConfirm: true,
        archiveSelected: true,
        bulkActionFinished: (failedIds: string[]) => ({ failedIds }),
        restoreSessions: (sessionIds: string[]) => ({ sessionIds }),
    }),
    reducers({
        selection: [
            EMPTY_SELECTION,
            {
                setSelection: (_, { selection }) => selection,
                toggleSessionSelection: (state, { sessionId }) => toggleSelection(state, sessionId),
                clearSelection: () => EMPTY_SELECTION,
                // A partial failure keeps only the failures selected, so a retry is one click.
                bulkActionFinished: (state, { failedIds }) =>
                    failedIds.length ? { ids: failedIds, anchorId: state.anchorId } : EMPTY_SELECTION,
                locationChanged: () => EMPTY_SELECTION,
                setView: () => EMPTY_SELECTION,
                setTypes: () => EMPTY_SELECTION,
                setFilters: () => EMPTY_SELECTION,
                clearFilters: () => EMPTY_SELECTION,
            },
        ],
        bulkAction: [
            null as TodayBulkAction | null,
            {
                pinSelected: () => 'pin',
                fileSelectedTo: () => 'file',
                archiveSelected: () => 'archive',
                bulkActionFinished: () => null,
            },
        ],
        bulkArchiveConfirm: [
            CLOSED_BULK_ARCHIVE_CONFIRM,
            {
                openBulkArchiveConfirm: (_, { count, running }) => ({ open: true, count, running }),
                closeBulkArchiveConfirm: (state) => ({ ...state, open: false }),
                bulkActionFinished: (state) => ({ ...state, open: false }),
            },
        ],
    }),
    selectors({
        feedSessions: [
            (s) => [s.feedSections],
            (feedSections: SpaceFeedSection[]): TodayWorkItem[] => spaceFeedSessions(feedSections),
        ],
        orderedSessionIds: [
            (s) => [s.feedSessions],
            (feedSessions: TodayWorkItem[]): string[] => feedSessions.map((item) => item.id),
        ],
        // Sessions that leave the feed, like archived ones, drop out of the selection.
        selectedSessionIds: [
            (s) => [s.selection, s.orderedSessionIds],
            (selection: TodaySessionSelection, orderedSessionIds: string[]): string[] =>
                pruneToVisible(selection.ids, orderedSessionIds),
        ],
        selectedSessions: [
            (s) => [s.selectedSessionIds, s.feedSessions],
            (selectedSessionIds: string[], feedSessions: TodayWorkItem[]): TodayWorkItem[] => {
                const items = new Map(feedSessions.map((item) => [item.id, item]))
                return selectedSessionIds.flatMap((id) => items.get(id) ?? [])
            },
        ],
        selectAll: [
            (s) => [s.selectedSessionIds, s.orderedSessionIds],
            (selectedSessionIds: string[], orderedSessionIds: string[]): SpaceFeedSelectAllState =>
                selectAllState(selectedSessionIds, orderedSessionIds),
        ],
        bulkPinDirection: [
            (s) => [s.selectedSessionIds, s.pinnedItems],
            (selectedSessionIds: string[], pinnedItems: TodayWorkItem[]): 'pin' | 'unpin' =>
                computeBulkPinDirection(selectedSessionIds, new Set(pinnedItems.map((item) => item.id))),
        ],
        runningSelectedCount: [
            (s) => [s.selectedSessions],
            (selectedSessions: TodayWorkItem[]): number =>
                selectedSessions.filter((item) => activeCloudRunId(item) !== null).length,
        ],
    }),
    listeners(({ actions, values }) => {
        const teamId = (): string => String(values.currentTeamId)

        const finish = (failedIds: string[]): void => {
            actions.bulkActionFinished(failedIds)
            actions.loadSessions()
            actions.loadPinnedTasks()
            actions.loadRecentTasks()
        }

        return {
            selectSessionRange: ({ sessionId }) => {
                actions.setSelection(
                    computeRangeSelection(
                        values.selection.anchorId,
                        sessionId,
                        values.orderedSessionIds,
                        values.selectedSessionIds
                    )
                )
            },
            toggleSelectAll: () => {
                actions.setSelection(toggleAllSelection(values.selectedSessionIds, values.orderedSessionIds))
            },
            pinSelected: async () => {
                const ids = values.selectedSessionIds
                const pinned = values.bulkPinDirection === 'pin'
                const failed = await pinSessions(teamId(), ids, pinned)
                reportBulkResult(pinned ? 'pin' : 'unpin', ids.length, failed.length)
                finish(failed)
            },
            fileSelectedTo: async ({ spaceId }) => {
                const ids = values.selectedSessionIds
                const failed = await fileSessions(teamId(), ids, spaceId)
                reportBulkResult('file', ids.length, failed.length)
                finish(failed)
            },
            requestBulkArchive: () => {
                if (values.runningSelectedCount > 0) {
                    actions.openBulkArchiveConfirm(values.selectedSessionIds.length, values.runningSelectedCount)
                } else {
                    actions.archiveSelected()
                }
            },
            archiveSelected: async () => {
                const ids = values.selectedSessions.map((item) => item.id)
                const failed = await archiveSessions(teamId(), values.selectedSessions)
                const archivedIds = ids.filter((id) => !failed.includes(id))
                reportBulkResult('archive', ids.length, failed.length, () => actions.restoreSessions(archivedIds))
                finish(failed)
            },
            restoreSessions: async ({ sessionIds }) => {
                const failed = await restoreSessions(teamId(), sessionIds)
                if (failed.length) {
                    reportBulkResult('restore', sessionIds.length, failed.length)
                }
                actions.loadSessions()
                actions.loadPinnedTasks()
                actions.loadRecentTasks()
            },
        }
    }),
    afterMount(({ actions, values, cache }) => {
        cache.disposables.add(() => {
            const onKeyDown = (event: KeyboardEvent): void => {
                // The archive confirm answers Escape itself, and the selection it names has to stay.
                if (
                    event.key === 'Escape' &&
                    !isEditableTarget(event.target) &&
                    !isMenuEscape(event) &&
                    !values.bulkArchiveConfirm.open &&
                    values.selection.ids.length
                ) {
                    actions.clearSelection()
                }
            }
            window.addEventListener('keydown', onKeyDown)
            return () => window.removeEventListener('keydown', onKeyDown)
        }, 'clearSelectionOnEscape')
    }),
])
