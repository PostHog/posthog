export const loopSceneLogic = kea<loopSceneLogicType>([
    path((id) => ['products', 'tasks', 'loops', 'loopSceneLogic', id]),
    props({} as LoopSceneLogicProps),
    key((props) => props.id),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], userLogic, ['user']],
        actions: [loopsLogic, ['loadLoopsPage']],
    })),
    actions({
        setFormValues: (values: Partial<LoopFormValues>) => ({ values }),
        resetForm: true,
        saveLoop: true,
        loopSaved: (loop: LoopDTOApi) => ({ loop }),
        runLoop: true,
        setEnabled: (enabled: boolean) => ({ enabled }),
        deleteLoop: true,
        requestFinished: true,
    }),
    loaders(({ props, values }) => ({
        loop: [
            null as LoopDTOApi | null,
            {
                loadLoop: async () =>
                    props.id !== NEW_LOOP_ID && values.currentTeamId
                        ? await loopsRetrieve(String(values.currentTeamId), props.id)
                        : null,
            },
        ],
        runs: [
            null as LoopRunDTOApi[] | null,
            {
                loadRuns: async () =>
                    props.id !== NEW_LOOP_ID && values.currentTeamId
                        ? (
                              await loopsRunsRetrieve(String(values.currentTeamId), props.id, {
                                  limit: RECENT_RUNS_LIMIT,
                              })
                          ).results
                        : null,
            },
        ],
    })),
    reducers({
        loop: {
            loopSaved: (_, { loop }) => loop,
        },
        formValues: [
            emptyLoopFormValues(),
            {
                setFormValues: (state, { values }) => ({ ...state, ...values }),
            },
        ],
        // Errors show only after the first save attempt, so an empty new form does not open in red.
        showErrors: [
            false,
            {
                saveLoop: () => true,
                loopSaved: () => false,
            },
        ],
        loopMissing: [
            false,
            {
                loadLoopFailure: (_, { errorObject }) => (errorObject as { status?: number })?.status === 404,
            },
        ],
        loopUnavailable: [
            false,
            {
                loadLoop: () => false,
                loadLoopFailure: () => true,
            },
        ],
        saving: [false, { saveLoop: () => true, loopSaved: () => false, requestFinished: () => false }],
        running: [false, { runLoop: () => true, requestFinished: () => false }],
        togglingEnabled: [false, { setEnabled: () => true, loopSaved: () => false, requestFinished: () => false }],
        deleting: [false, { deleteLoop: () => true, requestFinished: () => false }],
    }),
    selectors({
        isNew: [(_, p) => [p.id], (id: string): boolean => id === NEW_LOOP_ID],
        formError: [(s) => [s.formValues], (formValues: LoopFormValues): string | null => loopFormError(formValues)],
        patch: [
            (s) => [s.loop, s.formValues],
            (loop: LoopDTOApi | null, formValues: LoopFormValues): PatchedLoopWriteApi =>
                loop ? loopPatch(loop, formValues) : {},
        ],
        saveDisabledReason: [
            (s) => [s.isNew, s.loop, s.patch, s.formError, s.showErrors],
            (
                isNew: boolean,
                loop: LoopDTOApi | null,
                patch: PatchedLoopWriteApi,
                formError: string | null,
                showErrors: boolean
            ): string | null => {
                if (!isNew && !loop) {
                    return 'The loop is still loading'
                }
                if (!isNew && Object.keys(patch).length === 0) {
                    return 'No changes to save'
                }
                return showErrors ? formError : null
            },
        ],
        runDisabledReason: [
            (s) => [s.loop, s.patch],
            (loop: LoopDTOApi | null, patch: PatchedLoopWriteApi): string | null => {
                if (!loop) {
                    return 'Save the loop first'
                }
                if (Object.keys(patch).length > 0) {
                    return 'Save or discard your changes first'
                }
                return null
            },
        ],
        // Matches the backend: on a team loop, only its owner can change what the agent does and how it starts.
        ownerOnlyDisabledReason: [
            (s) => [s.loop, s.user],
            (loop: LoopDTOApi | null, user: UserType | null): string | null =>
                loop && loop.visibility === 'team' && loop.created_by_id !== user?.id
                    ? 'Only the owner of this loop can change this'
                    : null,
        ],
        breadcrumbs: [
            (s) => [s.loop, s.isNew, (_, props) => props],
            (loop: LoopDTOApi | null, isNew: boolean, props: LoopSceneLogicProps): Breadcrumb[] => [
                {
                    key: [Scene.TaskLoop, props.id],
                    name: isNew ? 'New loop' : (loop?.name ?? 'Loop'),
                    path: urls.taskLoop(props.id),
                    iconType: 'task',
                },
            ],
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadLoopSuccess: ({ loop }) => {
            if (loop) {
                actions.setFormValues(loopToFormValues(loop))
                // pinned: analytics event names and properties match PostHog Desktop, so one insight covers both
                posthog.capture('Loop viewed', {
                    source: 'web',
                    loop_id: loop.id,
                    visibility: loop.visibility,
                    enabled: loop.enabled,
                    disabled_reason: loop.disabled_reason,
                    last_run_status: loop.last_run_status,
                    ...triggerProperties(loop),
                })
            }
        },
        resetForm: () => {
            actions.setFormValues(values.loop ? loopToFormValues(values.loop) : emptyLoopFormValues())
        },
        saveLoop: async () => {
            const projectId = String(values.currentTeamId)
            if (values.formError) {
                actions.requestFinished()
                return
            }
            try {
                if (values.isNew) {
                    const loop = await loopsCreate(projectId, formValuesToLoopWrite(values.formValues))
                    posthog.capture('Loop created', {
                        source: 'web',
                        loop_id: loop.id,
                        visibility: loop.visibility,
                        repository_count: loop.repositories.length,
                        ...triggerProperties(loop),
                    })
                    toast.success({ title: 'Loop created' })
                    actions.loopSaved(loop)
                    actions.loadLoopsPage()
                    router.actions.replace(urls.taskLoop(loop.id))
                    return
                }
                const patch = values.patch
                const loop = await loopsPartialUpdate(projectId, props.id, patch)
                posthog.capture('Loop updated', {
                    source: 'web',
                    loop_id: loop.id,
                    changed_fields: Object.keys(patch),
                    ...triggerProperties(loop),
                })
                toast.success({ title: 'Loop saved' })
                actions.loopSaved(loop)
                actions.setFormValues(loopToFormValues(loop))
                actions.loadLoopsPage()
            } catch (error) {
                toast.error({ title: errorDetail(error, 'Couldn’t save the loop. Try again.') })
                actions.requestFinished()
            }
        },
        runLoop: async () => {
            try {
                const result = await loopsRunCreate(String(values.currentTeamId), props.id)
                if (result.created) {
                    posthog.capture('Loop run started', { source: 'web', loop_id: props.id })
                    toast.success({ title: 'Run started' })
                    actions.loadRuns()
                } else {
                    posthog.capture('Loop run blocked', { source: 'web', loop_id: props.id, reason: result.reason })
                    toast.error({ title: loopRunBlockedMessage(result.reason) })
                }
            } catch (error) {
                toast.error({ title: errorDetail(error, 'Couldn’t start a run. Try again.') })
            }
            actions.requestFinished()
        },
        setEnabled: async ({ enabled }) => {
            try {
                const loop = await loopsPartialUpdate(String(values.currentTeamId), props.id, { enabled })
                posthog.capture('Loop enabled toggled', { source: 'web', loop_id: props.id, enabled })
                actions.loopSaved(loop)
                actions.loadLoopsPage()
            } catch (error) {
                toast.error({
                    title: errorDetail(error, `Couldn’t ${enabled ? 'resume' : 'pause'} the loop. Try again.`),
                })
                actions.requestFinished()
            }
        },
        deleteLoop: async () => {
            try {
                await loopsDestroy(String(values.currentTeamId), props.id)
                posthog.capture('Loop deleted', { source: 'web', loop_id: props.id })
                toast.success({ title: 'Loop deleted' })
                actions.loadLoopsPage()
                router.actions.push(urls.projectHomepage())
            } catch (error) {
                toast.error({ title: errorDetail(error, 'Couldn’t delete the loop. Try again.') })
            }
            actions.requestFinished()
        },
    })),
    afterMount(({ actions, props }) => {
        if (props.id !== NEW_LOOP_ID) {
            actions.loadLoop()
            actions.loadRuns()
        }
    }),
])
