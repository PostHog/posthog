import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { getCurrentTeamId } from 'lib/utils/getAppContext'
import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { todaySpacesLogic } from '~/layout/today/todaySpacesLogic'
import { Breadcrumb } from '~/types'

import { ChannelDTOApi, TaskListItemApi } from '../generated/api.schemas'
import { newSessionSpace } from '../spaces/newSessionSceneLogic'
import { SpaceComposerRepositoryConfig, spaceComposerRepositoryConfig } from '../spaces/spaceSceneLogic'
import {
    CommandCenterCells,
    CommandCenterLayout,
    layoutCellCount,
    placeSession,
    resizeCells,
} from './commandCenterGrid'

/** `picked` is a session from the tile's list, `started` is one the tile's composer created. */
export type CommandCenterSessionSource = 'picked' | 'started'

const DEFAULT_LAYOUT: CommandCenterLayout = '2x2'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface commandCenterSceneLogicValues {
    lastSpaceId: string | null // todaySpacesLogic
    recentTasks: TaskListItemApi[] // todaySpacesLogic
    recentTasksLoading: boolean // todaySpacesLogic
    sortedSpaces: ChannelDTOApi[] // todaySpacesLogic
    spacesLoading: boolean // todaySpacesLogic
    spacesUnavailable: boolean // todaySpacesLogic
    breadcrumbs: Breadcrumb[]
    cells: CommandCenterCells
    composerRepositoryConfig: SpaceComposerRepositoryConfig
    composerSpace: ChannelDTOApi | null
    composingIndex: number | null
    layout: CommandCenterLayout
    pickableSessionIds: string[]
    sessionTitles: Map<string, string>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface commandCenterSceneLogicActions {
    loadSpaces: () => any // todaySpacesLogic
    clearTile: (index: number) => {
        index: number
    }
    placeSession: (
        index: number,
        sessionId: string,
        source: CommandCenterSessionSource
    ) => {
        index: number
        sessionId: string
        source: CommandCenterSessionSource
    }
    setLayout: (layout: CommandCenterLayout) => {
        layout: CommandCenterLayout
    }
    startComposing: (index: number) => {
        index: number
    }
    stopComposing: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface commandCenterSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        composerSpace: (sortedSpaces: ChannelDTOApi[], lastSpaceId: string | null) => ChannelDTOApi | null
        composerRepositoryConfig: (composerSpace: ChannelDTOApi | null) => SpaceComposerRepositoryConfig
        sessionTitles: (recentTasks: TaskListItemApi[]) => Map<string, string>
        pickableSessionIds: (recentTasks: TaskListItemApi[], cells: CommandCenterCells) => string[]
    }
}

export type commandCenterSceneLogicType = MakeLogicType<
    commandCenterSceneLogicValues,
    commandCenterSceneLogicActions,
    Record<string, any>,
    commandCenterSceneLogicMeta
>

export const commandCenterSceneLogic = kea<commandCenterSceneLogicType>([
    path(['products', 'tasks', 'commandCenter', 'commandCenterSceneLogic']),
    connect(() => ({
        values: [
            todaySpacesLogic,
            ['lastSpaceId', 'recentTasks', 'recentTasksLoading', 'sortedSpaces', 'spacesLoading', 'spacesUnavailable'],
        ],
        actions: [todaySpacesLogic, ['loadSpaces']],
    })),
    actions({
        setLayout: (layout: CommandCenterLayout) => ({ layout }),
        placeSession: (index: number, sessionId: string, source: CommandCenterSessionSource) => ({
            index,
            sessionId,
            source,
        }),
        clearTile: (index: number) => ({ index }),
        startComposing: (index: number) => ({ index }),
        stopComposing: true,
    }),
    reducers(() => ({
        // Session ids belong to one project, so each project keeps its own grid.
        layout: [
            DEFAULT_LAYOUT as CommandCenterLayout,
            { persist: true, prefix: `${getCurrentTeamId()}__` },
            { setLayout: (_, { layout }) => layout },
        ],
        cells: [
            resizeCells([], layoutCellCount(DEFAULT_LAYOUT)),
            { persist: true, prefix: `${getCurrentTeamId()}__` },
            {
                setLayout: (cells, { layout }) => resizeCells(cells, layoutCellCount(layout)),
                placeSession: (cells, { index, sessionId }) => placeSession(cells, index, sessionId),
                clearTile: (cells, { index }) => cells.map((cell, cellIndex) => (cellIndex === index ? null : cell)),
            },
        ],
        // One tile at a time composes a new session, like PostHog Desktop.
        composingIndex: [
            null as number | null,
            {
                startComposing: (_, { index }) => index,
                stopComposing: () => null,
                placeSession: () => null,
                setLayout: () => null,
            },
        ],
    })),
    selectors({
        composerSpace: [
            (s) => [s.sortedSpaces, s.lastSpaceId],
            (sortedSpaces: ChannelDTOApi[], lastSpaceId: string | null): ChannelDTOApi | null =>
                newSessionSpace(sortedSpaces, null, lastSpaceId).space,
        ],
        composerRepositoryConfig: [
            (s) => [s.composerSpace],
            (composerSpace: ChannelDTOApi | null): SpaceComposerRepositoryConfig =>
                spaceComposerRepositoryConfig(composerSpace),
        ],
        sessionTitles: [
            (s) => [s.recentTasks],
            (recentTasks: TaskListItemApi[]): Map<string, string> =>
                new Map(recentTasks.map((task) => [task.id, task.title || 'Untitled session'])),
        ],
        pickableSessionIds: [
            (s) => [s.recentTasks, s.cells],
            (recentTasks: TaskListItemApi[], cells: CommandCenterCells): string[] =>
                recentTasks.filter((task) => !task.archived && !cells.includes(task.id)).map((task) => task.id),
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                { key: Scene.TaskSpaces, name: 'Spaces', path: urls.taskSpaces(), iconType: 'task' },
                {
                    key: Scene.TaskCommandCenter,
                    name: 'Command center',
                    path: urls.taskCommandCenter(),
                    iconType: 'task',
                },
            ],
        ],
    }),
    listeners(({ values }) => ({
        setLayout: ({ layout }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('command center layout changed', { layout })
        },
        placeSession: ({ source }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('command center session placed', {
                source,
                layout: values.layout,
                filled_tiles: values.cells.filter(Boolean).length,
            })
        },
    })),
])
