export const taskAnalysisSceneLogic = kea<taskAnalysisSceneLogicType>([
    path(['products', 'tasks', 'frontend', 'logics', 'taskAnalysisSceneLogic']),

    connect(() => ({
        values: [projectLogic, ['currentProjectId'], modelCatalogueLogic, ['catalogue']],
    })),

    actions({
        setDraft: (draft: Partial<AIRunPreferenceDraft>) => ({ draft }),
        submitDraft: true,
    }),

    reducers({
        draftState: [
            UNTOUCHED_EMPTY_DRAFT,
            {
                setDraft: (state, { draft }) => ({ draft: { ...state.draft, ...draft }, touched: true }),
                loadPreferencesSuccess: (state, { preferences }) =>
                    state.touched ? state : { draft: draftFromStored(preferences), touched: false },
                savePreferencesSuccess: (_, { preferences }) => ({
                    draft: draftFromStored(preferences),
                    touched: false,
                }),
            },
        ],
    }),

    loaders(({ values }) => ({
        preferences: {
            __default: null as TasksAIRunPreferencesApi | null,
            loadPreferences: async (): Promise<TasksAIRunPreferencesApi | null> => {
                if (values.currentProjectId == null) {
                    return null
                }
                return (await tasksAnalysisConfigList(String(values.currentProjectId))).analysis_run_preferences
            },
            savePreferences: async (
                preferences: TasksAIRunPreferencesApi
            ): Promise<TasksAIRunPreferencesApi | null> => {
                const response = await tasksAnalysisConfigCreate(String(values.currentProjectId), preferences)
                lemonToast.success(preferences.model ? 'Analysis model saved' : 'Back to the built-in analysis model')
                return response.analysis_run_preferences
            },
        },
        runs: {
            __default: null as TaskAnalysisRunApi[] | null,
            loadRuns: async (): Promise<TaskAnalysisRunApi[] | null> => {
                if (values.currentProjectId == null) {
                    return null
                }
                return (await tasksAnalysisRunsList(String(values.currentProjectId), { limit: RUNS_PAGE_SIZE })).results
            },
        },
    })),

    selectors({
        draft: [(s) => [s.draftState], (state: DraftState): AIRunPreferenceDraft => state.draft],
        draftDirty: [
            (s) => [s.draft, s.preferences],
            (draft: AIRunPreferenceDraft, stored: TasksAIRunPreferencesApi | null): boolean =>
                isDraftChanged(draft, draftFromStored(stored)),
        ],
    }),

    listeners(({ actions, values }) => ({
        submitDraft: () => {
            actions.savePreferences(payloadFromDraft(values.draft, values.catalogue))
        },
    })),

    afterMount(({ actions }) => {
        actions.loadPreferences()
        actions.loadRuns()
    }),
])
