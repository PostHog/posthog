import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { subscriptions } from 'kea-subscriptions'

import { teamLogic } from 'scenes/teamLogic'

import { teamSharedAgentServers } from 'products/mcp_store/frontend/gateway/agentServerUtils'
import {
    mcpGatewayServersToolsRetrieve,
    mcpGatewayServiceAccountsList,
} from 'products/mcp_store/frontend/generated/api'
import type {
    MCPServiceAccountApi,
    MCPServiceAccountServerApi,
    MCPToolApprovalStateEnumApi,
    ResolvedToolPolicyApi,
} from 'products/mcp_store/frontend/generated/api.schemas'

export type ServerToolPolicyCounts = Record<MCPToolApprovalStateEnumApi, number>

