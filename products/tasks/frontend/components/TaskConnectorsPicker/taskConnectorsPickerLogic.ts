/** The MCP servers a workflow's "Create AI task" step can pick from: what the workflow agent reaches. */
export const taskConnectorsPickerLogic = kea<taskConnectorsPickerLogicType>([
    path(['products', 'tasks', 'frontend', 'components', 'TaskConnectorsPicker', 'taskConnectorsPickerLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        loadToolPolicies: (serverId: string) => ({ serverId }),
        loadToolPoliciesSuccess: (serverId: string, tools: ResolvedToolPolicyApi[]) => ({ serverId, tools }),
        loadToolPoliciesFailure: (serverId: string) => ({ serverId }),
    }),
    loaders(({ values }) => ({
        serviceAccounts: [
            [] as MCPServiceAccountApi[],
            {
                loadServiceAccounts: async (): Promise<MCPServiceAccountApi[]> => {
                    if (values.currentTeamId === null) {
                        return []
                    }
                    const response = await mcpGatewayServiceAccountsList(String(values.currentTeamId), { limit: 500 })
                    return response.results
                },
            },
        ],
    })),
    reducers({
        // Kept apart from "loaded nothing" so the empty state never shows after a failed load.
        serviceAccountsFailed: [
            false,
            {
                loadServiceAccounts: () => false,
                loadServiceAccountsFailure: () => true,
            },
        ],
        toolPoliciesByServer: [
            {} as Record<string, ResolvedToolPolicyApi[] | 'error'>,
            {
                // A team switch reloads the catalog, so stale per-server results reset with it.
                loadServiceAccounts: () => ({}),
                loadToolPoliciesSuccess: (state, { serverId, tools }) => ({ ...state, [serverId]: tools }),
                loadToolPoliciesFailure: (state, { serverId }) => ({ ...state, [serverId]: 'error' }),
            },
        ],
    }),
    selectors({
        workflowAccount: [
            (s) => [s.serviceAccounts],
            (serviceAccounts: MCPServiceAccountApi[]): MCPServiceAccountApi | null =>
                serviceAccounts.find((account) => account.agent_key === 'workflow') ?? null,
        ],
        // Workflow runs have no credential owner, so they mount team shares only: offer exactly those.
        teamWorkflowServers: [
            (s) => [s.workflowAccount],
            (workflowAccount: MCPServiceAccountApi | null): MCPServiceAccountServerApi[] =>
                teamSharedAgentServers(workflowAccount?.servers ?? []),
        ],
        toolPolicyCountsByServer: [
            (s) => [s.toolPoliciesByServer],
            (
                toolPoliciesByServer: Record<string, ResolvedToolPolicyApi[] | 'error'>
            ): Record<string, ServerToolPolicyCounts | 'error'> =>
                Object.fromEntries(
                    Object.entries(toolPoliciesByServer).map(([serverId, tools]) => {
                        if (tools === 'error') {
                            return [serverId, 'error']
                        }
                        const counts: ServerToolPolicyCounts = { approved: 0, needs_approval: 0, do_not_use: 0 }
                        for (const tool of tools) {
                            counts[tool.policy_state] += 1
                        }
                        return [serverId, counts]
                    })
                ),
        ],
    }),
    listeners(({ actions, values }) => ({
        loadServiceAccountsSuccess: () => {
            for (const server of values.teamWorkflowServers) {
                actions.loadToolPolicies(server.id)
            }
        },
        loadToolPolicies: async ({ serverId }) => {
            const account = values.workflowAccount
            if (values.currentTeamId === null || account === null) {
                return
            }
            try {
                const response = await mcpGatewayServersToolsRetrieve(String(values.currentTeamId), serverId, {
                    scope_type: 'agent',
                    scope_service_account_id: account.id,
                })
                actions.loadToolPoliciesSuccess(serverId, [...response.results])
            } catch {
                actions.loadToolPoliciesFailure(serverId)
            }
        },
    })),
    subscriptions(({ actions }) => ({
        currentTeamId: () => {
            actions.loadServiceAccounts()
        },
    })),
])
