import {
    dataCatalogCertificationsCertifyCreate,
    dataCatalogCertificationsCreate,
    dataCatalogCertificationsDeprecateCreate,
    dataCatalogCertificationsDestroy,
    dataCatalogCertificationsList,
} from './generated/api'
import type { DataCatalogCertificationApi } from './generated/api.schemas'

export type CertificationTargetType = 'table' | 'view'
export type ProposedStatus = 'certified' | 'deprecated'
export type CertificationStatusFilter = 'all' | 'proposed' | 'certified' | 'deprecated'

export interface CertificationsFilters {
    search: string
    status: CertificationStatusFilter
}

export const DEFAULT_CERTIFICATIONS_FILTERS: CertificationsFilters = {
    search: '',
    status: 'all',
}

export interface NewCertificationForm {
    targetId: string
    targetName: string
    targetType: CertificationTargetType
    notes: string
    proposedStatus: ProposedStatus
}

export const EMPTY_NEW_CERTIFICATION_FORM: NewCertificationForm = {
    targetId: '',
    targetName: '',
    targetType: 'table',
    notes: '',
    proposedStatus: 'certified',
}

function projectId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

function apiErrorDetail(error: unknown): string | null {
    return error instanceof ApiError ? error.detail : null
}

const searchCertifications = createFuseSearch<DataCatalogCertificationApi>(['target_name', 'target_type', 'notes'])

