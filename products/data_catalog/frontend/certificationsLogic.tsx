export const certificationsLogic = kea<certificationsLogicType>([
    path(['products', 'data_catalog', 'frontend', 'certificationsLogic']),
    connect(() => ({
        actions: [databaseTableListLogic, ['loadDatabase']],
    })),
    actions({
        setFilters: (filters: Partial<CertificationsFilters>) => ({ filters }),
        openNewCertificationModal: true,
        closeNewCertificationModal: true,
        setNewCertificationForm: (form: Partial<NewCertificationForm>) => ({ form }),
        createCertification: true,
        setCreatingCertification: (creating: boolean) => ({ creating }),
        certifyCertification: (id: string) => ({ id }),
        deprecateCertification: (id: string) => ({ id }),
        revokeCertification: (id: string) => ({ id }),
        setActionInFlight: (id: string, inFlight: boolean) => ({ id, inFlight }),
    }),
    loaders(() => ({
        certifications: [
            [] as DataCatalogCertificationApi[],
            {
                loadCertifications: async () => {
                    const response = await dataCatalogCertificationsList(projectId())
                    return response.results || []
                },
            },
        ],
    })),
    reducers({
        filters: [
            DEFAULT_CERTIFICATIONS_FILTERS as CertificationsFilters,
            {
                setFilters: (state, { filters }) => ({ ...state, ...filters }),
            },
        ],
        newCertificationModalOpen: [
            false,
            {
                openNewCertificationModal: () => true,
                closeNewCertificationModal: () => false,
            },
        ],
        newCertificationForm: [
            EMPTY_NEW_CERTIFICATION_FORM as NewCertificationForm,
            {
                setNewCertificationForm: (state, { form }) => ({ ...state, ...form }),
                openNewCertificationModal: () => EMPTY_NEW_CERTIFICATION_FORM,
                closeNewCertificationModal: () => EMPTY_NEW_CERTIFICATION_FORM,
            },
        ],
        isCreatingCertification: [
            false,
            {
                setCreatingCertification: (_, { creating }) => creating,
            },
        ],
        actionsInFlight: [
            {} as Record<string, boolean>,
            {
                setActionInFlight: (state, { id, inFlight }) => ({ ...state, [id]: inFlight }),
            },
        ],
    }),
    selectors({
        filteredCertifications: [
            (s) => [s.certifications, s.filters],
            (certifications: DataCatalogCertificationApi[], filters: CertificationsFilters) => {
                const statusMatched =
                    filters.status === 'all'
                        ? certifications
                        : certifications.filter((certification) => certification.status === filters.status)
                return searchCertifications(statusMatched, filters.search)
            },
        ],
        proposedCount: [
            (s) => [s.certifications],
            (certifications: DataCatalogCertificationApi[]) =>
                certifications.filter((certification) => certification.status === 'proposed').length,
        ],
    }),
    listeners(({ values, actions }) => {
        // certify and deprecate share a body: both replace the row in place from the response.
        const runReviewAction = async (
            id: string,
            request: () => Promise<DataCatalogCertificationApi>,
            failureMessage: string
        ): Promise<void> => {
            if (values.actionsInFlight[id]) {
                return
            }
            actions.setActionInFlight(id, true)
            try {
                const updated = await request()
                actions.loadCertificationsSuccess(
                    values.certifications.map((certification) => (certification.id === id ? updated : certification))
                )
                // Badges elsewhere read certification state off the shared schema, so refresh it.
                actions.loadDatabase({ force: true })
            } catch (error) {
                lemonToast.error(apiErrorDetail(error) || failureMessage)
            } finally {
                actions.setActionInFlight(id, false)
            }
        }

        return {
            openNewCertificationModal: () => actions.loadDatabase(),
            createCertification: async () => {
                if (values.isCreatingCertification) {
                    return
                }
                actions.setCreatingCertification(true)
                const form = values.newCertificationForm
                try {
                    const created = await dataCatalogCertificationsCreate(projectId(), {
                        ...(form.targetId
                            ? form.targetType === 'view'
                                ? { saved_query_id: form.targetId }
                                : { table_id: form.targetId }
                            : form.targetType === 'view'
                              ? { view_name: form.targetName }
                              : { table_name: form.targetName }),
                        notes: form.notes || undefined,
                        proposed_status: form.proposedStatus,
                    })
                    actions.loadCertificationsSuccess([created, ...values.certifications])
                    actions.closeNewCertificationModal()
                    lemonToast.success(
                        form.proposedStatus === 'deprecated' ? 'Deprecation proposed' : 'Certification proposed'
                    )
                } catch (error) {
                    lemonToast.error(apiErrorDetail(error) || 'Could not create the proposal. Try again.')
                } finally {
                    actions.setCreatingCertification(false)
                }
            },
            certifyCertification: async ({ id }) =>
                runReviewAction(
                    id,
                    () => dataCatalogCertificationsCertifyCreate(projectId(), id),
                    'Could not certify. Try again.'
                ),
            deprecateCertification: async ({ id }) =>
                runReviewAction(
                    id,
                    () => dataCatalogCertificationsDeprecateCreate(projectId(), id),
                    'Could not deprecate. Try again.'
                ),
            revokeCertification: async ({ id }) => {
                if (values.actionsInFlight[id]) {
                    return
                }
                actions.setActionInFlight(id, true)
                try {
                    await dataCatalogCertificationsDestroy(projectId(), id)
                    actions.loadCertificationsSuccess(
                        values.certifications.filter((certification) => certification.id !== id)
                    )
                    // Badges elsewhere read certification state off the shared schema, so refresh it.
                    actions.loadDatabase({ force: true })
                    lemonToast.success('Certification revoked')
                } catch (error) {
                    lemonToast.error(apiErrorDetail(error) || 'Could not revoke the certification. Try again.')
                } finally {
                    actions.setActionInFlight(id, false)
                }
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadCertifications()
    }),
])
