import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiConfig, ApiError } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'

import { dataCatalogUsageLatestRetrieve, dataCatalogUsageList, dataCatalogUsageRecomputeCreate } from './generated/api'
import type {
    DataCatalogMetricApi,
    TopicClusterApi,
    UncoveredGroupApi,
    UsageSnapshotApi,
    UsageSnapshotSummaryApi,
} from './generated/api.schemas'
import { metricsLogic } from './metricsLogic'
import { MetricUsageRow, buildMetricUsageRows } from './usageRows'

/** The latest finished scan, `'none'` when no scan has finished, and null until the first load answers. */
export type LatestScan = UsageSnapshotApi | 'none' | null

function projectId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface usageLogicValues {
    allMetrics: DataCatalogMetricApi[] // metricsLogic
    failureReasons: Record<string, string>
    history: UsageSnapshotSummaryApi[] | null
    historyLoading: boolean
    includeScouts: boolean
    latest: LatestScan
    latestLoadFailed: boolean
    latestLoading: boolean
    metricNames: Record<string, string>
    metricRows: MetricUsageRow[]
    newestScan: UsageSnapshotSummaryApi | null
    recomputed: UsageSnapshotSummaryApi | null
    recomputedLoading: boolean
    scanRunning: boolean
    topics: TopicClusterApi[]
    uncovered: UncoveredGroupApi[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface usageLogicActions {
    loadHistory: () => any
    loadHistoryFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadHistorySuccess: (
        history: UsageSnapshotSummaryApi[],
        payload?: any
    ) => {
        history: UsageSnapshotSummaryApi[]
        payload?: any
    }
    loadLatest: () => any
    loadLatestFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadLatestSuccess: (
        latest: LatestScan,
        payload?: any
    ) => {
        latest: LatestScan
        payload?: any
    }
    recompute: () => any
    recomputeFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    recomputeSuccess: (
        recomputed: UsageSnapshotSummaryApi,
        payload?: any
    ) => {
        recomputed: UsageSnapshotSummaryApi
        payload?: any
    }
    setIncludeScouts: (includeScouts: boolean) => {
        includeScouts: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface usageLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        newestScan: (history: UsageSnapshotSummaryApi[] | null) => UsageSnapshotSummaryApi | null
        scanRunning: (newestScan: UsageSnapshotSummaryApi | null) => boolean
        metricNames: (allMetrics: DataCatalogMetricApi[]) => Record<string, string>
        metricRows: (
            latest: LatestScan,
            metricNames: Record<string, string>,
            includeScouts: boolean
        ) => MetricUsageRow[]
        topics: (latest: LatestScan) => TopicClusterApi[]
        uncovered: (latest: LatestScan) => UncoveredGroupApi[]
        failureReasons: (latest: LatestScan) => Record<string, string>
    }
}

export type usageLogicType = MakeLogicType<usageLogicValues, usageLogicActions, Record<string, any>, usageLogicMeta>

export const usageLogic = kea<usageLogicType>([
    path(['products', 'data_catalog', 'frontend', 'usageLogic']),
    connect(() => ({
        values: [metricsLogic, ['allMetrics']],
    })),
    actions({
        setIncludeScouts: (includeScouts: boolean) => ({ includeScouts }),
    }),
    loaders({
        history: [
            null as UsageSnapshotSummaryApi[] | null,
            {
                loadHistory: async () => dataCatalogUsageList(projectId()),
            },
        ],
        latest: [
            null as LatestScan,
            {
                loadLatest: async (): Promise<LatestScan> => {
                    try {
                        return await dataCatalogUsageLatestRetrieve(projectId())
                    } catch (error) {
                        if (error instanceof ApiError && error.status === 404) {
                            return 'none'
                        }
                        throw error
                    }
                },
            },
        ],
        recomputed: [
            null as UsageSnapshotSummaryApi | null,
            {
                recompute: async () => dataCatalogUsageRecomputeCreate(projectId()),
            },
        ],
    }),
    reducers({
        includeScouts: [
            false,
            {
                setIncludeScouts: (_, { includeScouts }) => includeScouts,
            },
        ],
        latestLoadFailed: [
            false,
            {
                loadLatest: () => false,
                loadLatestFailure: () => true,
            },
        ],
    }),
    selectors({
        newestScan: [
            (s) => [s.history],
            (history: UsageSnapshotSummaryApi[] | null): UsageSnapshotSummaryApi | null => history?.[0] ?? null,
        ],
        scanRunning: [
            (s) => [s.newestScan],
            (newestScan: UsageSnapshotSummaryApi | null): boolean => newestScan?.status === 'computing',
        ],
        metricNames: [
            (s) => [s.allMetrics],
            (allMetrics: DataCatalogMetricApi[]): Record<string, string> =>
                Object.fromEntries(allMetrics.map((metric) => [metric.id, metric.display_name || metric.name])),
        ],
        metricRows: [
            (s) => [s.latest, s.metricNames, s.includeScouts],
            (latest: LatestScan, metricNames: Record<string, string>, includeScouts: boolean): MetricUsageRow[] =>
                latest && latest !== 'none' ? buildMetricUsageRows(latest.payload, metricNames, includeScouts) : [],
        ],
        topics: [
            (s) => [s.latest],
            (latest: LatestScan): TopicClusterApi[] =>
                latest && latest !== 'none' ? (latest.payload.topics ?? []) : [],
        ],
        uncovered: [
            (s) => [s.latest],
            (latest: LatestScan): UncoveredGroupApi[] =>
                latest && latest !== 'none' ? (latest.payload.uncovered ?? []) : [],
        ],
        failureReasons: [
            (s) => [s.latest],
            (latest: LatestScan): Record<string, string> =>
                latest && latest !== 'none'
                    ? Object.fromEntries(
                          latest.payload.failed_sections.map((failure) => [failure.section, failure.reason])
                      )
                    : {},
        ],
    }),
    listeners(({ actions }) => ({
        recomputeSuccess: () => {
            lemonToast.success('Usage scan started. Results appear here when it finishes.')
            actions.loadHistory()
        },
        recomputeFailure: ({ errorObject }) => {
            const detail = errorObject instanceof ApiError ? errorObject.detail : null
            lemonToast.error(detail || 'Could not start the usage scan. Try again in a minute.')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadHistory()
        actions.loadLatest()
    }),
])
