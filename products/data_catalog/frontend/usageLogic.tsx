export type usageLogicType = MakeLogicType<usageLogicValues, usageLogicActions, Record<string, any>, usageLogicMeta>

export const usageLogic = kea<usageLogicType>([
    path(['products', 'data_catalog', 'frontend', 'usageLogic']),
    connect(() => ({
        values: [metricsLogic, ['allMetrics', 'metricsLoadState']],
    })),
    loaders({
        history: [
            null as UsageSnapshotSummaryApi[] | null,
            {
                loadHistory: async () => dataCatalogUsageList(projectId()),
            },
        ],
        latest: [
            null as LatestScan,
            {
                loadLatest: async (): Promise<LatestScan> =>
                    noneWhenNoScan(dataCatalogUsageLatestRetrieve(projectId())),
            },
        ],
        recomputed: [
            null as UsageSnapshotSummaryApi | null,
            {
                recompute: async () => dataCatalogUsageRecomputeCreate(projectId()),
            },
        ],
    }),
    reducers({
        latestLoadFailed: [
            false,
            {
                loadLatest: () => false,
                loadLatestFailure: () => true,
            },
        ],
        // The backend answers 404 on the history when usage is off for the team or the deployment can't scan.
        usageUnavailable: [
            false,
            {
                loadHistorySuccess: () => false,
                loadHistoryFailure: (_, { errorObject }) =>
                    errorObject instanceof ApiError && errorObject.status === 404,
            },
        ],
    }),
    selectors({
        newestScan: [
            (s) => [s.history],
            (history: UsageSnapshotSummaryApi[] | null): UsageSnapshotSummaryApi | null => history?.[0] ?? null,
        ],
        scanRunning: [
            (s) => [s.newestScan],
            (newestScan: UsageSnapshotSummaryApi | null): boolean => newestScan?.status === 'computing',
        ],
        // Without the history, a scan may already be running, so a click could start a second one.
        recomputeDisabledReason: [
            (s) => [s.history, s.historyLoading, s.scanRunning],
            (
                history: UsageSnapshotSummaryApi[] | null,
                historyLoading: boolean,
                scanRunning: boolean
            ): string | null => {
                if (scanRunning) {
                    return 'A scan is already running'
                }
                if (history === null) {
                    return historyLoading
                        ? 'Checking whether a scan is running'
                        : "Couldn't check whether a scan is running. Refresh the page."
                }
                return null
            },
        ],
        metricNames: [
            (s) => [s.allMetrics],
            (allMetrics: DataCatalogMetricApi[]): Record<string, string> =>
                Object.fromEntries(allMetrics.map((metric) => [metric.id, metric.display_name || metric.name])),
        ],
        sourceRows: [
            (s) => [s.latest, s.metricNames, s.metricsLoadState],
            // The rows wait for the catalog, so a metric shows its name rather than its id.
            (
                latest: LatestScan,
                metricNames: Record<string, string>,
                metricsLoadState: MetricsLoadState
            ): SourceRow[] =>
                latest && latest !== 'none' && metricsLoadState !== 'unknown'
                    ? buildSourceRows(latest.payload, metricNames)
                    : [],
        ],
        topics: [
            (s) => [s.latest],
            (latest: LatestScan): TopicClusterApi[] =>
                latest && latest !== 'none' ? (latest.payload.topics ?? []) : [],
        ],
        metricsById: [
            (s) => [s.allMetrics],
            (allMetrics: DataCatalogMetricApi[]): Record<string, DataCatalogMetricApi> =>
                Object.fromEntries(allMetrics.map((metric) => [metric.id, metric])),
        ],
        proposedRows: [
            (s) => [s.latest],
            (latest: LatestScan): ProposedRow[] =>
                latest && latest !== 'none' ? buildProposedRows(latest.payload) : [],
        ],
        topicSessionsSummary: [
            (s) => [s.latest],
            (latest: LatestScan): string | null =>
                latest && latest !== 'none' && latest.payload.topic_sessions
                    ? describeTopicSessions(latest.payload.topic_sessions)
                    : null,
        ],
        failureReasons: [
            (s) => [s.latest],
            (latest: LatestScan): Partial<Record<UsageSectionEnumApi, string>> =>
                latest && latest !== 'none'
                    ? Object.fromEntries(
                          latest.payload.failed_sections.map((failure) => [failure.section, failure.reason])
                      )
                    : {},
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadHistorySuccess: async (_, breakpoint) => {
            cache.failedPolls = 0
            if (values.scanRunning) {
                cache.sawRunningScan = true
                await breakpoint(SCAN_POLL_INTERVAL_MS)
                actions.loadHistory()
            } else if (cache.sawRunningScan) {
                cache.sawRunningScan = false
                actions.loadLatest()
            }
        },
        loadHistoryFailure: async (_, breakpoint) => {
            // A failed poll keeps the last history, so a scan that was running still needs a poll.
            if (values.scanRunning) {
                cache.failedPolls = (cache.failedPolls ?? 0) + 1
                await breakpoint(Math.min(SCAN_POLL_INTERVAL_MS * 2 ** cache.failedPolls, MAX_POLL_BACKOFF_MS))
                actions.loadHistory()
            }
        },
        recomputeSuccess: () => {
            lemonToast.success('Usage scan started. Results appear here when it finishes.')
            actions.loadHistory()
        },
        recomputeFailure: ({ errorObject }) => {
            const detail = errorObject instanceof ApiError ? errorObject.detail : null
            lemonToast.error(detail || 'Could not start the usage scan. Try again in a minute.')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadHistory()
        actions.loadLatest()
    }),
])
