import { MakeLogicType, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiConfig, ApiError } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'

import { noneWhenNoScan } from './common'
import { dataCatalogUsageLatestRetrieve, dataCatalogUsageList, dataCatalogUsageRecomputeCreate } from './generated/api'
import type {
    DataCatalogMetricApi,
    TopicClusterApi,
    UsageSnapshotApi,
    UsageSectionEnumApi,
    UsageSnapshotSummaryApi,
} from './generated/api.schemas'
import { MetricsLoadState, metricsLogic } from './metricsLogic'
import { ProposedRow, buildProposedRows } from './proposedRows'
import { SourceRow, buildSourceRows, describeTopicSessions } from './usageRows'

// A scan takes minutes to hours, so a slow poll is enough to show its results without a refresh.
const SCAN_POLL_INTERVAL_MS = 30000
const MAX_POLL_BACKOFF_MS = 5 * 60 * 1000

/** The latest finished scan, `'none'` when no scan has finished, and null until the first load answers. */
export type LatestScan = UsageSnapshotApi | 'none' | null

function projectId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface usageLogicValues {
    allMetrics: DataCatalogMetricApi[] // metricsLogic
    metricsLoadState: MetricsLoadState // metricsLogic
    failureReasons: Partial<Record<UsageSectionEnumApi, string>>
    history: UsageSnapshotSummaryApi[] | null
    historyLoading: boolean
    latest: LatestScan
    latestLoadFailed: boolean
    latestLoading: boolean
    metricNames: Record<string, string>
    metricsById: Record<string, DataCatalogMetricApi>
    newestScan: UsageSnapshotSummaryApi | null
    proposedRows: ProposedRow[]
    recomputeDisabledReason: string | null
    recomputed: UsageSnapshotSummaryApi | null
    recomputedLoading: boolean
    scanRunning: boolean
    sourceRows: SourceRow[]
    topicSessionsSummary: string | null
    topics: TopicClusterApi[]
    usageUnavailable: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface usageLogicActions {
    loadHistory: () => any
    loadHistoryFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadHistorySuccess: (
        history: UsageSnapshotSummaryApi[],
        payload?: any
    ) => {
        history: UsageSnapshotSummaryApi[]
        payload?: any
    }
    loadLatest: () => any
    loadLatestFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadLatestSuccess: (
        latest: LatestScan,
        payload?: any
    ) => {
        latest: LatestScan
        payload?: any
    }
    recompute: () => any
    recomputeFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    recomputeSuccess: (
        recomputed: UsageSnapshotSummaryApi,
        payload?: any
    ) => {
        recomputed: UsageSnapshotSummaryApi
        payload?: any
    }
}

