const SQL_PREVIEW_QUERY_TAGS = { productKey: ProductKey.DATA_CATALOG, scene: 'DataCatalogNewMetric' }

const SQL_PREVIEW_FAILED_MESSAGE = "Couldn't run the query. Try again, or open it in the SQL editor to see more."

function insightTypeName(query: unknown): string | null {
    const node = query as { kind?: NodeKind; source?: { kind?: NodeKind } } | null
    const kind = node?.kind === NodeKind.InsightVizNode ? node.source?.kind : node?.kind
    return (kind && QUERY_TYPES_METADATA[kind]?.name) || null
}

function definitionRequest(
    form: NewMetricFormValues
): Pick<MetricCreateRequest, 'definition' | 'source_insight_short_id'> {
    if (form.definitionType === 'insight') {
        return { source_insight_short_id: form.sourceInsightShortId }
    }
    if (form.definitionType === 'sql') {
        return { definition: { kind: HOGQL_METRIC_DEFINITION_KIND, query: form.sql.trim() } }
    }
    return { definition: { kind: 'MarkdownDefinition', markdown: form.markdown } }
}

function definitionError(form: NewMetricFormValues): string | undefined {
    if (form.definitionType === 'sql') {
        return !form.sql.trim() ? 'Write the query that returns this metric' : undefined
    }
    if (form.definitionType === 'insight') {
        return !form.sourceInsightShortId ? 'Choose an insight' : undefined
    }
    if (!form.markdown.trim()) {
        return 'Write how to calculate this metric'
    }
    return form.markdown.length > METRIC_MARKDOWN_MAX_LENGTH
        ? `Keep the definition under ${METRIC_MARKDOWN_MAX_LENGTH.toLocaleString()} characters`
        : undefined
}

