export const dataCatalogNewMetricSceneLogic = kea<dataCatalogNewMetricSceneLogicType>([
    path(['products', 'data_catalog', 'frontend', 'dataCatalogNewMetricSceneLogic']),
    connect(() => ({
        values: [metricsLogic, ['allMetrics']],
        actions: [metricsLogic, ['loadMetricsSuccess']],
    })),
    actions({
        submitMetric: (approve: boolean) => ({ approve }),
        saveMetric: (form: NewMetricFormValues, approve: boolean, overwrite: boolean) => ({
            form,
            approve,
            overwrite,
        }),
        setSaving: (saving: MetricSaveAction | null) => ({ saving }),
        setInsightSearch: (search: string) => ({ search }),
        setSqlEditorError: (error: string | null) => ({ error }),
        testSqlQuery: true,
        openInSqlEditor: true,
        setLeaving: true,
    }),
    loaders(({ values }) => ({
        savedInsights: [
            [] as SavedInsightOption[],
            {
                loadSavedInsights: async (_, breakpoint) => {
                    await breakpoint(300)
                    const response = await api.insights.list({
                        saved: true,
                        basic: true,
                        limit: 100,
                        search: values.insightSearch || undefined,
                    })
                    breakpoint()
                    return (response.results || [])
                        .filter((insight) => !!insight.short_id)
                        .map((insight) => ({
                            short_id: insight.short_id as string,
                            label: insight.name || insight.derived_name || (insight.short_id as string),
                            typeName: insightTypeName(insight.query),
                        }))
                },
            },
        ],
        sqlPreview: [
            null as SqlPreview | null,
            {
                runSqlPreview: async (_, breakpoint) => {
                    const sql = values.metricForm.sql.trim()
                    if (!sql) {
                        return null
                    }
                    const response = await performQuery<HogQLQuery>(
                        { kind: NodeKind.HogQLQuery, query: sql, tags: SQL_PREVIEW_QUERY_TAGS },
                        undefined,
                        'force_blocking'
                    )
                    breakpoint()
                    return {
                        sql,
                        columns: response.columns ?? [],
                        rows: (response.results ?? []) as unknown[][],
                        hasMore: !!response.hasMore,
                        warnings: (response.warnings ?? []).map((warning) => warning.message),
                    }
                },
            },
        ],
    })),
    reducers({
        approveOnCreate: [
            true,
            {
                submitMetric: (_, { approve }) => approve,
            },
        ],
        saving: [
            null as MetricSaveAction | null,
            {
                setSaving: (_, { saving }) => saving,
            },
        ],
        insightSearch: [
            '',
            {
                setInsightSearch: (_, { search }) => search,
            },
        ],
        sqlPreviewError: [
            null as string | null,
            {
                runSqlPreview: () => null,
                runSqlPreviewSuccess: () => null,
                runSqlPreviewFailure: (_, { errorObject }) => errorObject?.detail ?? SQL_PREVIEW_FAILED_MESSAGE,
            },
        ],
        savedInsightsFailed: [
            false,
            {
                loadSavedInsights: () => false,
                loadSavedInsightsFailure: () => true,
            },
        ],
        sqlEditorError: [
            null as string | null,
            {
                setSqlEditorError: (_, { error }) => error,
            },
        ],
        leaving: [
            false,
            {
                setLeaving: () => true,
            },
        ],
    }),
    forms(({ actions, values }) => ({
        metricForm: {
            defaults: EMPTY_NEW_METRIC_FORM,
            errors: (form: NewMetricFormValues) => ({
                display_name: !form.display_name.trim() ? 'Name the metric' : undefined,
                name: form.display_name.trim() ? validateMetricName(form.name.trim()) : undefined,
                description: !form.description.trim()
                    ? 'Add a description'
                    : validateMetricDescription(form.description.trim()),
                sql: form.definitionType === 'sql' ? definitionError(form) : undefined,
                sourceInsightShortId: form.definitionType === 'insight' ? definitionError(form) : undefined,
                markdown: form.definitionType === 'markdown' ? definitionError(form) : undefined,
            }),
            submit: (form: NewMetricFormValues) => {
                actions.saveMetric(form, values.approveOnCreate, false)
            },
        },
    })),
    selectors({
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                { key: 'DataCatalog', name: 'Data catalog', path: urls.dataCatalog() },
                { key: 'DataCatalogNewMetric', name: 'New metric' },
            ],
        ],
        sqlSourceQuery: [
            (s) => [s.metricForm],
            (form: NewMetricFormValues): HogQLQuery => ({ kind: NodeKind.HogQLQuery, query: form.sql }),
        ],
        sqlPreviewStale: [
            (s) => [s.sqlPreview, s.metricForm],
            (sqlPreview: SqlPreview | null, form: NewMetricFormValues): boolean =>
                !!sqlPreview && sqlPreview.sql !== form.sql.trim(),
        ],
        sqlNameTaken: [
            (s) => [s.allMetrics, s.metricForm],
            (allMetrics: DataCatalogMetricApi[], form: NewMetricFormValues): boolean =>
                !!form.name.trim() && allMetrics.some((metric) => metric.name === form.name.trim()),
        ],
        selectedInsight: [
            (s) => [s.savedInsights, s.metricForm],
            (savedInsights: SavedInsightOption[], form: NewMetricFormValues): SavedInsightOption | null =>
                savedInsights.find((insight) => insight.short_id === form.sourceInsightShortId) ?? null,
        ],
        metricsUsingSelectedInsight: [
            (s) => [s.allMetrics, s.metricForm],
            (allMetrics: DataCatalogMetricApi[], form: NewMetricFormValues): string[] =>
                form.sourceInsightShortId
                    ? allMetrics
                          .filter((metric) => metric.source_insight_short_id === form.sourceInsightShortId)
                          .map((metric) => metric.name)
                    : [],
        ],
    }),
    listeners(({ actions, values }) => ({
        submitMetric: () => {
            actions.submitMetricForm()
        },
        submitMetricFormFailure: () => {
            scrollToFormError()
        },
        setInsightSearch: () => {
            actions.loadSavedInsights(undefined)
        },
        setMetricFormValue: ({ name, value }) => {
            const field = Array.isArray(name) ? name[0] : name
            if (field !== 'sourceInsightShortId' || values.metricForm.display_name.trim()) {
                return
            }
            const insight = values.savedInsights.find((option) => option.short_id === value)
            if (insight && !values.metricForm.name.trim()) {
                actions.setMetricFormValues({
                    display_name: insight.label,
                    name: sqlNameFromDisplayName(insight.label),
                })
            }
        },
        testSqlQuery: () => {
            if (!values.sqlPreviewLoading) {
                actions.runSqlPreview(undefined)
            }
        },
        openInSqlEditor: () => {
            const { sql, name, display_name, description, unit } = values.metricForm
            actions.setLeaving()
            router.actions.push(
                urls.sqlEditor({
                    query: sql,
                    source: 'metric',
                    metricPrefill: { name, display_name, description, unit },
                })
            )
        },
        saveMetric: async ({ form, approve, overwrite }) => {
            if (values.saving) {
                return
            }
            actions.setSaving(approve ? 'approve' : 'propose')
            try {
                const created = await createMetricAsUser(
                    {
                        name: form.name.trim(),
                        display_name: form.display_name.trim(),
                        description: form.description.trim(),
                        unit: form.unit.trim(),
                        ...definitionRequest(form),
                        overwrite,
                    },
                    approve
                )
                actions.loadMetricsSuccess([
                    created.metric,
                    ...values.allMetrics.filter((metric) => metric.name !== created.metric.name),
                ])
                toastCreatedMetric(created, overwrite)
                actions.setLeaving()
                router.actions.push(urls.dataCatalogMetric(created.metric.name))
            } catch (error) {
                actions.setSaving(null)
                const existing = existingMetricFromNameConflict(error)
                if (existing) {
                    openOverwriteMetricDialog({
                        existing,
                        onOverwrite: () => actions.saveMetric(form, approve, true),
                    })
                    return
                }
                lemonToast.error(
                    (error instanceof ApiError && error.detail) ||
                        'Could not create the metric. Check the fields and try again.'
                )
            }
        },
    })),
    beforeUnload(({ values }) => ({
        enabled: () => values.metricFormChanged && !values.leaving,
        message: 'Your new metric has not been saved. Leave and discard it?',
    })),
    afterMount(({ actions, values }) => {
        actions.loadSavedInsights(undefined)
        void values.allMetrics
    }),
])
