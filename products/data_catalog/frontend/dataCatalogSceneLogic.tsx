import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { urls } from 'scenes/urls'

import { catalogRestructureEnabled } from 'products/data_modeling/frontend/catalogRestructure'

import { PROPOSED_TABLES_FILTER, TABLES_FILTER_PARAM, TABLES_SEARCH_PARAM } from './catalogTableRows'
import { dataCatalogAgentSyncLogic } from './dataCatalogAgentSyncLogic'

export type DataCatalogTab =
    | 'overview'
    | 'tables'
    | 'lineage'
    | 'metrics'
    | 'relationships'
    | 'data-quality'
    | 'certifications'
    | 'usage'
    | 'suggestions'

const CATALOG_TABS: DataCatalogTab[] = ['metrics', 'relationships', 'certifications']
const SECTION_TABS: DataCatalogTab[] = ['overview', 'tables', 'lineage', 'metrics', 'relationships', 'data-quality']
const FOLDED_INTO_TABLES: DataCatalogTab[] = ['certifications']

// pinned: analytics event name and properties, renaming breaks the insights built on them
export const SECTION_VIEWED_EVENT = 'data catalog section viewed'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataCatalogSceneLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    receivedFeatureFlags: boolean // featureFlagLogic
    activeTab: DataCatalogTab
    availableTabs: DataCatalogTab[]
    defaultTab: DataCatalogTab
    lineageVisited: boolean
    reportedSection: DataCatalogTab | null
    restructureEnabled: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataCatalogSceneLogicActions {
    setFeatureFlags: (
        flags: string[],
        variants: Record<string, boolean | string>
    ) => {
        flags: string[]
        variants: Record<string, boolean | string>
    } // featureFlagLogic
    reportSectionViewed: (section: DataCatalogTab) => {
        section: DataCatalogTab
    }
    setActiveTab: (activeTab: DataCatalogTab) => {
        activeTab: DataCatalogTab
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataCatalogSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        restructureEnabled: (featureFlags: FeatureFlagsSet) => boolean
        availableTabs: (restructureEnabled: boolean, featureFlags: FeatureFlagsSet) => DataCatalogTab[]
        defaultTab: (restructureEnabled: boolean) => DataCatalogTab
    }
}

export type dataCatalogSceneLogicType = MakeLogicType<
    dataCatalogSceneLogicValues,
    dataCatalogSceneLogicActions,
    Record<string, any>,
    dataCatalogSceneLogicMeta
>

export const dataCatalogSceneLogic = kea<dataCatalogSceneLogicType>([
    path(['products', 'data_catalog', 'frontend', 'dataCatalogSceneLogic']),
    connect(() => ({
        logic: [dataCatalogAgentSyncLogic],
        values: [featureFlagLogic, ['featureFlags', 'receivedFeatureFlags']],
        actions: [featureFlagLogic, ['setFeatureFlags']],
    })),
    actions({
        setActiveTab: (activeTab: DataCatalogTab) => ({ activeTab }),
        reportSectionViewed: (section: DataCatalogTab) => ({ section }),
    }),
    reducers({
        activeTab: [
            'metrics' as DataCatalogTab,
            {
                setActiveTab: (_, { activeTab }) => activeTab,
            },
        ],
        // Holds the last reported section, so a URL change inside a section, such as a filter, reports nothing.
        reportedSection: [
            null as DataCatalogTab | null,
            {
                reportSectionViewed: (_, { section }) => section,
            },
        ],
        lineageVisited: [
            false,
            {
                setActiveTab: (visited, { activeTab }) => visited || activeTab === 'lineage',
            },
        ],
    }),
    selectors({
        restructureEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => catalogRestructureEnabled(featureFlags),
        ],
        availableTabs: [
            (s) => [s.restructureEnabled, s.featureFlags],
            (restructureEnabled: boolean, featureFlags: FeatureFlagsSet): DataCatalogTab[] => {
                if (!restructureEnabled) {
                    return featureFlags[FEATURE_FLAGS.DATA_CATALOG_USAGE] ? [...CATALOG_TABS, 'usage'] : CATALOG_TABS
                }
                return [
                    ...SECTION_TABS,
                    ...(featureFlags[FEATURE_FLAGS.DATA_MODELING_USAGE] ? (['usage'] as const) : []),
                    ...(featureFlags[FEATURE_FLAGS.WAREHOUSE_SUGGESTIONS] ? (['suggestions'] as const) : []),
                ]
            },
        ],
        defaultTab: [
            (s) => [s.restructureEnabled],
            (restructureEnabled: boolean): DataCatalogTab => (restructureEnabled ? 'overview' : 'metrics'),
        ],
    }),
    listeners(({ actions, values }) => ({
        reportSectionViewed: ({ section }) => {
            posthog.capture(SECTION_VIEWED_EVENT, {
                section,
                layout: values.restructureEnabled ? 'restructured' : 'classic',
            })
        },
        setFeatureFlags: () => {
            // On a cold load the flags can arrive after the URL, so check a usage link again once they do.
            const onCatalog = removeProjectIdIfPresent(router.values.location.pathname) === urls.dataCatalog()
            const requested = router.values.searchParams.tab
            const tab = values.availableTabs.includes(requested) ? requested : values.defaultTab
            if (!onCatalog) {
                return
            }
            if (tab !== values.activeTab) {
                actions.setActiveTab(tab)
            }
            if (tab !== values.reportedSection) {
                actions.reportSectionViewed(tab)
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setActiveTab: () => {
            if ((router.values.searchParams.tab ?? values.defaultTab) !== values.activeTab) {
                return urls.dataCatalog(values.activeTab === values.defaultTab ? undefined : values.activeTab)
            }
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.dataCatalog()]: (_, searchParams, hashParams) => {
            if (values.restructureEnabled && FOLDED_INTO_TABLES.includes(searchParams.tab)) {
                router.actions.replace(
                    urls.dataCatalog(),
                    {
                        ...searchParams,
                        tab: 'tables',
                        [TABLES_FILTER_PARAM]: searchParams[TABLES_SEARCH_PARAM] ? undefined : PROPOSED_TABLES_FILTER,
                    },
                    hashParams
                )
                return
            }
            const tab = values.availableTabs.includes(searchParams.tab) ? searchParams.tab : values.defaultTab
            if (tab !== values.activeTab) {
                actions.setActiveTab(tab)
            }
            // Before the flags arrive, the layout is not known yet. The flags listener reports the view then.
            if (values.receivedFeatureFlags && tab !== values.reportedSection) {
                actions.reportSectionViewed(tab)
            }
        },
    })),
])
