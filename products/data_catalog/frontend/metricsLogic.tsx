import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api, { ApiConfig, ApiError } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { createFuse } from 'lib/utils/fuseSearch'

import {
    dataCatalogMetricsApproveCreate,
    dataCatalogMetricsCreate,
    dataCatalogMetricsDestroy,
    dataCatalogMetricsList,
    dataCatalogMetricsRefreshFromInsightCreate,
} from './generated/api'
import type { DataCatalogMetricApi } from './generated/api.schemas'

export type MetricStatusFilter = 'all' | 'proposed' | 'approved'

export interface MetricsFilters {
    search: string
    status: MetricStatusFilter
}

export const DEFAULT_METRICS_FILTERS: MetricsFilters = {
    search: '',
    status: 'all',
}

// SQL metrics are created from the SQL editor's "Save as metric", not this modal.
export type NewMetricDefinitionType = 'none' | 'markdown' | 'insight'

export interface NewMetricForm {
    name: string
    display_name: string
    description: string
    unit: string
    definitionType: NewMetricDefinitionType
    markdown: string
    sourceInsightShortId: string
}

export const EMPTY_NEW_METRIC_FORM: NewMetricForm = {
    name: '',
    display_name: '',
    description: '',
    unit: '',
    definitionType: 'none',
    markdown: '',
    sourceInsightShortId: '',
}

export interface SavedInsightOption {
    short_id: string
    label: string
}

const MARKDOWN_DEFINITION_KIND = 'MarkdownDefinition'

function projectId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

function buildDefinition(form: NewMetricForm): Record<string, unknown> | null {
    if (form.definitionType === 'markdown') {
        return { kind: MARKDOWN_DEFINITION_KIND, markdown: form.markdown }
    }
    return null
}

function apiErrorDetail(error: unknown): string | null {
    return error instanceof ApiError ? error.detail : null
}

