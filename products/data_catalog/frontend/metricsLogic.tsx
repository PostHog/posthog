export const metricsLogic = kea<metricsLogicType>([
    path(['products', 'data_catalog', 'frontend', 'metricsLogic']),
    connect(() => ({
        values: [userLogic, ['user']],
    })),
    actions({
        setFilters: (filters: Partial<MetricsFilters>) => ({ filters }),
        setCreatingMetricAs: (creatingAs: MetricSaveAction | null) => ({ creatingAs }),
        approveMetric: (name: string) => ({ name }),
        refreshMetricFromInsight: (name: string) => ({ name }),
        deleteMetric: (name: string) => ({ name }),
        setMetricOwner: (name: string, owner: string | null) => ({ name, owner }),
        setActionInFlight: (name: string, inFlight: boolean) => ({ name, inFlight }),
        bulkApproveMetrics: (names: string[], onSuccess?: () => void) => ({ names, onSuccess }),
        bulkDeleteMetrics: (names: string[], onSuccess?: () => void) => ({ names, onSuccess }),
        bulkChangeMetricOwner: (names: string[], owner: string | null, onSuccess?: () => void) => ({
            names,
            owner,
            onSuccess,
        }),
        setBulkActionInFlight: (bulkAction: BulkMetricAction | null) => ({ bulkAction }),
        openMetricFromInsightModal: true,
        closeMetricFromInsightModal: true,
        createMetricFromInsight: (request: MetricFromInsightRequest, approve: boolean, overwrite: boolean = false) => ({
            request,
            approve,
            overwrite,
        }),
    }),
    lazyLoaders(() => ({
        allMetrics: [
            [] as DataCatalogMetricApi[],
            {
                // Walk every page: the tab badge counts proposed metrics across the whole catalog,
                // and selection spans pages, so a single server page would hide the rest.
                loadMetrics: async () => {
                    const metrics: DataCatalogMetricApi[] = []
                    for (let offset = 0; ; offset += METRICS_PAGE_SIZE) {
                        const response = await dataCatalogMetricsList(projectId(), {
                            limit: METRICS_PAGE_SIZE,
                            offset,
                        })
                        metrics.push(...(response.results || []))
                        if (!response.next || !response.results?.length) {
                            return metrics
                        }
                    }
                },
            },
        ],
    })),
    reducers({
        filters: [
            DEFAULT_METRICS_FILTERS as MetricsFilters,
            {
                setFilters: (state, { filters }) => ({ ...state, ...filters }),
            },
        ],
        creatingMetricAs: [
            null as MetricSaveAction | null,
            {
                setCreatingMetricAs: (_, { creatingAs }) => creatingAs,
            },
        ],
        metricFromInsightModalOpen: [
            false,
            {
                openMetricFromInsightModal: () => true,
                closeMetricFromInsightModal: () => false,
            },
        ],
        actionsInFlight: [
            {} as Record<string, boolean>,
            {
                setActionInFlight: (state, { name, inFlight }) => ({ ...state, [name]: inFlight }),
            },
        ],
        bulkActionInFlight: [
            null as BulkMetricAction | null,
            {
                setBulkActionInFlight: (_, { bulkAction }) => bulkAction,
            },
        ],
    }),
    selectors({
        metrics: [
            (s) => [s.allMetrics, s.filters],
            (allMetrics: DataCatalogMetricApi[], filters: MetricsFilters) => {
                let results = allMetrics
                if (filters.status !== 'all') {
                    results = results.filter((metric) => metric.status === filters.status)
                }
                if (filters.createdBy) {
                    // created_by is SET_NULL on the model, so a deleted creator arrives as null despite the
                    // serializer type.
                    results = results.filter((metric) => metric.created_by?.uuid === filters.createdBy)
                }
                if (filters.owner) {
                    results = results.filter((metric) => metric.owner === filters.owner)
                }
                if (filters.search) {
                    const fuse = createFuse<DataCatalogMetricApi>(results, {
                        keys: ['name', 'display_name', 'description'],
                        threshold: 0.3,
                    })
                    results = fuse.search(filters.search).map((result) => result.item)
                }
                return results
            },
        ],
        ownerFilterOptions: [
            (s) => [s.allMetrics],
            (allMetrics: DataCatalogMetricApi[]): string[] =>
                [...new Set(allMetrics.flatMap((metric) => (metric.owner ? [metric.owner] : [])))].sort(),
        ],
        proposedCount: [
            (s) => [s.allMetrics],
            (allMetrics: DataCatalogMetricApi[]) => allMetrics.filter((metric) => metric.status === 'proposed').length,
        ],
    }),
    listeners(({ values, actions }) => ({
        setFilters: async ({ filters }, breakpoint) => {
            // The search box dispatches on every keystroke, so wait for typing to settle before reporting.
            await breakpoint(500)
            const { status, createdBy, owner, search } = values.filters
            const describeMember = (identifier: string | null, mine: string | undefined): string =>
                identifier ? (identifier === mine ? 'me' : 'other') : 'any'
            posthog.capture('data catalog metrics filtered', {
                changed_filters: Object.keys(filters),
                status,
                created_by: describeMember(createdBy, values.user?.uuid),
                owner: describeMember(owner, values.user?.email),
                has_search: search.length > 0,
                result_count: values.metrics.length,
            })
        },
        createMetricFromInsight: async ({ request, approve, overwrite }) => {
            if (values.creatingMetricAs) {
                return
            }
            actions.setCreatingMetricAs(approve ? 'approve' : 'propose')
            try {
                const created = await createMetricAsUser({ ...request, overwrite }, approve)
                actions.loadMetricsSuccess(withCreatedMetric(values.allMetrics, created.metric))
                actions.closeMetricFromInsightModal()
                toastCreatedMetric(created, overwrite, {
                    label: 'View metric',
                    action: () => router.actions.push(urls.dataCatalogMetric(created.metric.name)),
                })
            } catch (error) {
                const existing = existingMetricFromNameConflict(error)
                if (existing) {
                    openOverwriteMetricDialog({
                        existing,
                        onOverwrite: () => actions.createMetricFromInsight(request, approve, true),
                    })
                } else {
                    lemonToast.error(
                        apiErrorDetail(error) || 'Could not create the metric from this insight. Try again.'
                    )
                }
            } finally {
                actions.setCreatingMetricAs(null)
            }
        },
        approveMetric: async ({ name }) => {
            if (values.bulkActionInFlight || values.actionsInFlight[name]) {
                return
            }
            actions.setActionInFlight(name, true)
            try {
                const approved = await dataCatalogMetricsApproveCreate(projectId(), name)
                actions.loadMetricsSuccess(
                    values.allMetrics.map((metric) => (metric.name === name ? approved : metric))
                )
            } catch (error) {
                if (error instanceof ApiError && error.status === 409) {
                    lemonToast.error(
                        'This metric has drifted from its source insight and cannot be approved. Refresh it first.',
                        {
                            button: {
                                label: 'Refresh from insight',
                                action: () => actions.refreshMetricFromInsight(name),
                            },
                        }
                    )
                } else {
                    lemonToast.error(apiErrorDetail(error) || 'Could not approve the metric. Try again.')
                }
            } finally {
                actions.setActionInFlight(name, false)
            }
        },
        refreshMetricFromInsight: async ({ name }) => {
            if (values.bulkActionInFlight || values.actionsInFlight[name]) {
                return
            }
            actions.setActionInFlight(name, true)
            try {
                const refreshed = await dataCatalogMetricsRefreshFromInsightCreate(projectId(), name)
                actions.loadMetricsSuccess(
                    values.allMetrics.map((metric) => (metric.name === name ? refreshed : metric))
                )
                lemonToast.success('Metric refreshed from its source insight')
            } catch (error) {
                lemonToast.error(
                    apiErrorDetail(error) || 'Could not refresh the metric from its source insight. Try again.'
                )
            } finally {
                actions.setActionInFlight(name, false)
            }
        },
        setMetricOwner: async ({ name, owner }) => {
            if (values.bulkActionInFlight || values.actionsInFlight[name]) {
                return
            }
            actions.setActionInFlight(name, true)
            try {
                const saved = await dataCatalogMetricsPartialUpdate(projectId(), name, { owner })
                actions.loadMetricsSuccess(values.allMetrics.map((metric) => (metric.name === name ? saved : metric)))
                lemonToast.success('Owner changed')
            } catch (error) {
                lemonToast.error(apiErrorDetail(error) || 'Could not change the owner. Try again.')
            } finally {
                actions.setActionInFlight(name, false)
            }
        },
        deleteMetric: async ({ name }) => {
            if (values.bulkActionInFlight || values.actionsInFlight[name]) {
                return
            }
            actions.setActionInFlight(name, true)
            try {
                await dataCatalogMetricsDestroy(projectId(), name)
                actions.loadMetricsSuccess(values.allMetrics.filter((metric) => metric.name !== name))
                lemonToast.success('Metric deleted')
            } catch (error) {
                lemonToast.error(apiErrorDetail(error) || 'Could not delete the metric. Try again.')
            } finally {
                actions.setActionInFlight(name, false)
            }
        },
        bulkApproveMetrics: async ({ names, onSuccess }) => {
            if (values.bulkActionInFlight || names.some((name) => values.actionsInFlight[name])) {
                return
            }
            actions.setBulkActionInFlight('approve')
            try {
                const response = await dataCatalogMetricsBulkApproveCreate(projectId(), { names })
                const approvedByName = new Map(response.approved.map((metric) => [metric.name, metric]))
                actions.loadMetricsSuccess(values.allMetrics.map((metric) => approvedByName.get(metric.name) ?? metric))
                if (response.approved.length) {
                    lemonToast.success(`Approved ${metricCount(response.approved.length)}`)
                }
                if (response.skipped.length) {
                    lemonToast.warning(skippedMessage(response.skipped))
                    // A skipped metric kept the state the page rendered (e.g. still proposed, or no
                    // drift tag). Reload so the table matches the server the batch reconciled against.
                    actions.loadMetrics()
                }
                onSuccess?.()
            } catch (error) {
                lemonToast.error(apiErrorDetail(error) || 'Could not approve the selected metrics. Try again.')
            } finally {
                actions.setBulkActionInFlight(null)
            }
        },
        bulkChangeMetricOwner: async ({ names, owner, onSuccess }) => {
            if (values.bulkActionInFlight || names.some((name) => values.actionsInFlight[name])) {
                return
            }
            actions.setBulkActionInFlight('change_owner')
            try {
                const response = await dataCatalogMetricsBulkChangeOwnerCreate(projectId(), { names, owner })
                const updatedByName = new Map(response.updated.map((metric) => [metric.name, metric]))
                actions.loadMetricsSuccess(values.allMetrics.map((metric) => updatedByName.get(metric.name) ?? metric))
                if (response.updated.length) {
                    lemonToast.success(`Changed the owner of ${metricCount(response.updated.length)}`)
                }
                if (response.skipped.length) {
                    lemonToast.warning(skippedMessage(response.skipped))
                    actions.loadMetrics()
                }
                onSuccess?.()
            } catch (error) {
                lemonToast.error(
                    apiErrorDetail(error) || 'Could not change the owner of the selected metrics. Try again.'
                )
            } finally {
                actions.setBulkActionInFlight(null)
            }
        },
        bulkDeleteMetrics: async ({ names, onSuccess }) => {
            if (values.bulkActionInFlight || names.some((name) => values.actionsInFlight[name])) {
                return
            }
            actions.setBulkActionInFlight('delete')
            try {
                const response = await dataCatalogMetricsBulkDeleteCreate(projectId(), { names })
                const deleted = new Set(response.deleted)
                actions.loadMetricsSuccess(values.allMetrics.filter((metric) => !deleted.has(metric.name)))
                if (response.deleted.length) {
                    lemonToast.success(`Deleted ${metricCount(response.deleted.length)}`)
                }
                if (response.skipped.length) {
                    lemonToast.warning(skippedMessage(response.skipped))
                    // A skipped metric may already be gone server-side (e.g. "Not found") yet still
                    // shows in the table. Reload so the table matches the server.
                    actions.loadMetrics()
                }
                onSuccess?.()
            } catch (error) {
                lemonToast.error(apiErrorDetail(error) || 'Could not delete the selected metrics. Try again.')
            } finally {
                actions.setBulkActionInFlight(null)
            }
        },
    })),
])
