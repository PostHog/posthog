export type MetricStatusFilter = 'all' | 'proposed' | 'approved'

export type BulkMetricAction = 'approve' | 'delete'

const METRICS_PAGE_SIZE = 100

export interface MetricsFilters {
    search: string
    status: MetricStatusFilter
}

export const DEFAULT_METRICS_FILTERS: MetricsFilters = {
    search: '',
    status: 'all',
}

export type NewMetricDefinitionType = 'markdown' | 'insight' | 'sql'

export interface NewMetricForm {
    name: string
    display_name: string
    description: string
    unit: string
    definitionType: NewMetricDefinitionType
    sourceInsightShortId: string
}

export const EMPTY_NEW_METRIC_FORM: NewMetricForm = {
    name: '',
    display_name: '',
    description: '',
    unit: '',
    definitionType: 'sql',
    sourceInsightShortId: '',
}

export interface SavedInsightOption {
    short_id: string
    label: string
}

export interface MetricFromInsightRequest {
    name: string
    display_name: string
    description: string
    source_insight_short_id: string
}

function projectId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

function apiErrorDetail(error: unknown): string | null {
    return error instanceof ApiError ? error.detail : null
}

function skippedMessage(skipped: DataCatalogMetricBulkSkipApi[]): string {
    const countByReason = new Map<string, number>()
    for (const skip of skipped) {
        countByReason.set(skip.reason, (countByReason.get(skip.reason) || 0) + 1)
    }
    const reasons = [...countByReason.entries()].map(([reason, count]) => `${reason} (${count})`).join(', ')
    return `Skipped ${metricCount(skipped.length)}: ${reasons}`
}

