export const metricsLogic = kea<metricsLogicType>([
    path(['products', 'data_catalog', 'frontend', 'metricsLogic']),
    actions({
        setFilters: (filters: Partial<MetricsFilters>) => ({ filters }),
        openNewMetricModal: true,
        closeNewMetricModal: true,
        setNewMetricForm: (form: Partial<NewMetricForm>) => ({ form }),
        createMetric: true,
        setCreatingMetric: (creating: boolean) => ({ creating }),
        approveMetric: (name: string) => ({ name }),
        refreshMetricFromInsight: (name: string) => ({ name }),
        deleteMetric: (name: string) => ({ name }),
        setActionInFlight: (name: string, inFlight: boolean) => ({ name, inFlight }),
    }),
    loaders(() => ({
        allMetrics: [
            [] as DataCatalogMetricApi[],
            {
                loadMetrics: async () => {
                    const response = await dataCatalogMetricsList(projectId())
                    return response.results || []
                },
            },
        ],
        savedInsights: [
            [] as SavedInsightOption[],
            {
                loadSavedInsights: async () => {
                    const response = await api.insights.list({ saved: true, basic: true, limit: 300 })
                    return (response.results || [])
                        .filter((insight) => !!insight.short_id)
                        .map((insight) => ({
                            short_id: insight.short_id as string,
                            label: insight.name || insight.derived_name || (insight.short_id as string),
                        }))
                },
            },
        ],
    })),
    reducers({
        filters: [
            DEFAULT_METRICS_FILTERS as MetricsFilters,
            {
                setFilters: (state, { filters }) => ({ ...state, ...filters }),
            },
        ],
        newMetricModalOpen: [
            false,
            {
                openNewMetricModal: () => true,
                closeNewMetricModal: () => false,
            },
        ],
        newMetricForm: [
            EMPTY_NEW_METRIC_FORM as NewMetricForm,
            {
                setNewMetricForm: (state, { form }) => ({ ...state, ...form }),
                openNewMetricModal: () => EMPTY_NEW_METRIC_FORM,
                closeNewMetricModal: () => EMPTY_NEW_METRIC_FORM,
            },
        ],
        isCreatingMetric: [
            false,
            {
                setCreatingMetric: (_, { creating }) => creating,
            },
        ],
        actionsInFlight: [
            {} as Record<string, boolean>,
            {
                setActionInFlight: (state, { name, inFlight }) => ({ ...state, [name]: inFlight }),
            },
        ],
    }),
    selectors({
        metrics: [
            (s) => [s.allMetrics, s.filters],
            (allMetrics: DataCatalogMetricApi[], filters: MetricsFilters) => {
                let results = allMetrics
                if (filters.status !== 'all') {
                    results = results.filter((metric) => metric.status === filters.status)
                }
                if (filters.search) {
                    const fuse = createFuse<DataCatalogMetricApi>(results, {
                        keys: ['name', 'display_name', 'description'],
                        threshold: 0.3,
                    })
                    results = fuse.search(filters.search).map((result) => result.item)
                }
                return results
            },
        ],
        proposedCount: [
            (s) => [s.allMetrics],
            (allMetrics: DataCatalogMetricApi[]) => allMetrics.filter((metric) => metric.status === 'proposed').length,
        ],
    }),
    listeners(({ values, actions }) => ({
        openNewMetricModal: () => actions.loadSavedInsights(),
        createMetric: async () => {
            if (values.isCreatingMetric) {
                return
            }
            actions.setCreatingMetric(true)
            const form = values.newMetricForm
            try {
                const created = await dataCatalogMetricsCreate(projectId(), {
                    name: form.name,
                    display_name: form.display_name || undefined,
                    description: form.description,
                    unit: form.unit || undefined,
                    ...(form.definitionType === 'insight'
                        ? { source_insight_short_id: form.sourceInsightShortId }
                        : { definition: buildDefinition(form) }),
                    created_source: 'user',
                })
                actions.loadMetricsSuccess([created, ...values.allMetrics])
                actions.closeNewMetricModal()
                lemonToast.success('Metric created')
            } catch (error) {
                lemonToast.error(
                    apiErrorDetail(error) || 'Could not create the metric. Check the fields and try again.'
                )
            } finally {
                actions.setCreatingMetric(false)
            }
        },
        approveMetric: async ({ name }) => {
            if (values.actionsInFlight[name]) {
                return
            }
            actions.setActionInFlight(name, true)
            try {
                const approved = await dataCatalogMetricsApproveCreate(projectId(), name)
                actions.loadMetricsSuccess(
                    values.allMetrics.map((metric) => (metric.name === name ? approved : metric))
                )
            } catch (error) {
                if (error instanceof ApiError && error.status === 409) {
                    lemonToast.error(
                        'This metric has drifted from its source insight and cannot be approved. Refresh it first.',
                        {
                            button: {
                                label: 'Refresh from insight',
                                action: () => actions.refreshMetricFromInsight(name),
                            },
                        }
                    )
                } else {
                    lemonToast.error(apiErrorDetail(error) || 'Could not approve the metric. Try again.')
                }
            } finally {
                actions.setActionInFlight(name, false)
            }
        },
        refreshMetricFromInsight: async ({ name }) => {
            if (values.actionsInFlight[name]) {
                return
            }
            actions.setActionInFlight(name, true)
            try {
                const refreshed = await dataCatalogMetricsRefreshFromInsightCreate(projectId(), name)
                actions.loadMetricsSuccess(
                    values.allMetrics.map((metric) => (metric.name === name ? refreshed : metric))
                )
                lemonToast.success('Metric refreshed from its source insight')
            } catch (error) {
                lemonToast.error(
                    apiErrorDetail(error) || 'Could not refresh the metric from its source insight. Try again.'
                )
            } finally {
                actions.setActionInFlight(name, false)
            }
        },
        deleteMetric: async ({ name }) => {
            if (values.actionsInFlight[name]) {
                return
            }
            actions.setActionInFlight(name, true)
            try {
                await dataCatalogMetricsDestroy(projectId(), name)
                actions.loadMetricsSuccess(values.allMetrics.filter((metric) => metric.name !== name))
                lemonToast.success('Metric deleted')
            } catch (error) {
                lemonToast.error(apiErrorDetail(error) || 'Could not delete the metric. Try again.')
            } finally {
                actions.setActionInFlight(name, false)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadMetrics()
    }),
])
