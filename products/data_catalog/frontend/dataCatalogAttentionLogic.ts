export interface dataCatalogAttentionLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    attention: AttentionCounts
    attentionLoading: boolean
    hasFailures: boolean
    tabCounts: Partial<Record<DataCatalogTab, number>>
    totalCount: number
}

