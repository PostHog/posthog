export interface dataCatalogAttentionLogicActions {
    loadAttention: (_: void) => void
    loadAttentionFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAttentionSuccess: (
        attention: AttentionCounts,
        payload?: void
    ) => {
        attention: AttentionCounts
        payload?: void
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataCatalogAttentionLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        tabCounts: (attention: AttentionCounts) => Partial<Record<DataCatalogTab, number>>
        totalCount: (tabCounts: Partial<Record<DataCatalogTab, number>>) => number
        hasFailures: (attention: AttentionCounts) => boolean
    }
}

export type dataCatalogAttentionLogicType = MakeLogicType<
    dataCatalogAttentionLogicValues,
    dataCatalogAttentionLogicActions,
    Record<string, any>,
    dataCatalogAttentionLogicMeta
>

export const dataCatalogAttentionLogic = kea<dataCatalogAttentionLogicType>([
    path(['products', 'data_catalog', 'frontend', 'dataCatalogAttentionLogic']),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags']] })),
    loaders(({ values }) => ({
        attention: [
            NO_ATTENTION,
            {
                loadAttention: async (_: void, breakpoint) => {
                    await breakpoint(REFRESH_DEBOUNCE_MS)
                    if (!catalogRestructureEnabled(values.featureFlags)) {
                        return NO_ATTENTION
                    }
                    return await fetchAttentionCounts(String(ApiConfig.getCurrentTeamId()))
                },
            },
        ],
    })),
    selectors({
        tabCounts: [
            (s) => [s.attention],
            (attention: AttentionCounts): Partial<Record<DataCatalogTab, number>> => ({
                overview: attention.failingModels,
                tables: attention.proposedCertifications,
                metrics: attention.proposedMetrics,
                relationships: attention.proposedRelationships,
                'data-quality': attention.failingChecks,
            }),
        ],
        totalCount: [
            (s) => [s.tabCounts],
            (tabCounts: Partial<Record<DataCatalogTab, number>>): number =>
                Object.values(tabCounts).reduce((sum, count) => sum + count, 0),
        ],
        hasFailures: [
            (s) => [s.attention],
            (attention: AttentionCounts): boolean => attention.failingModels + attention.failingChecks > 0,
        ],
    }),
    listeners(({ actions, cache }) => ({
        loadAttentionSuccess: () => {
            cache.disposables.add(() => {
                const timerId = setTimeout(() => actions.loadAttention(), REFRESH_INTERVAL_MS)
                return () => clearTimeout(timerId)
            }, 'refreshTimeout')
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.disposables.add(
            () =>
                runWhenIdle(() => {
                    cache.disposables.dispose('idleLoad')
                    actions.loadAttention()
                }),
            'idleLoad'
        )
    }),
])

export function refreshDataCatalogAttention(): void {
    dataCatalogAttentionLogic.findMounted()?.actions.loadAttention()
}
