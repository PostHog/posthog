export type catalogSetupLogicType = MakeLogicType<
    catalogSetupLogicValues,
    catalogSetupLogicActions,
    Record<string, any>,
    catalogSetupLogicMeta
>

export const catalogSetupLogic = kea<catalogSetupLogicType>([
    path(['products', 'data_catalog', 'frontend', 'catalogSetupLogic']),
    connect(() => ({
        values: [
            metricsLogic,
            ['allMetrics', 'metricsLoadState'],
            projectLogic,
            ['currentProjectId'],
            userLogic,
            ['user'],
            aiShellLogic,
            ['isMaxAvailable', 'effectivePhaiView'],
        ],
        actions: [
            sidePanelStateLogic,
            ['openSidePanel'],
            userLogic,
            ['updateHasSeenProductIntroFor'],
            metricsLogic,
            ['loadMetrics', 'loadMetricsSuccess'],
        ],
    })),
    actions({
        startSetupWithPostHogAI: (source: CatalogSetupSource) => ({ source }),
        copyAgentSetupPrompt: (source: CatalogSetupSource) => ({ source }),
        dismissSetupBanner: true,
        reportSetupBannerShown: true,
        recordSetupStarted: true,
        rememberSetupIntent: (source: CatalogSetupSource) => ({ source }),
        resumeSetupIntent: true,
        watchForNewMetrics: true,
    }),
    reducers({
        // Hides the banner at once; the user record confirms the dismissal after it reloads.
        dismissedLocally: [
            false,
            {
                dismissSetupBanner: () => true,
                recordSetupStarted: () => true,
            },
        ],
    }),
    selectors({
        // Only the sandbox runtime has the catalog tools and loads bundled skills such as the setup skill.
        // The legacy chat reads team-stored skills only, so it cannot run the setup flow.
        postHogAISetupAvailable: [
            (s) => [s.isMaxAvailable, s.effectivePhaiView],
            (isMaxAvailable: boolean, effectivePhaiView: PhaiViewMode): boolean =>
                isMaxAvailable && effectivePhaiView === 'new',
        ],
        setupBannerDismissed: [
            (s) => [s.dismissedLocally, s.user],
            (dismissedLocally: boolean, user: UserType | null): boolean =>
                dismissedLocally ||
                !!user?.has_seen_product_intro_for?.[SETUP_BANNER_DISMISSED_KEY] ||
                !!user?.has_seen_product_intro_for?.[SETUP_STARTED_KEY],
        ],
        showSetupBanner: [
            (s) => [s.metricsLoadState, s.allMetrics, s.user, s.setupBannerDismissed],
            (
                metricsLoadState: MetricsLoadState,
                allMetrics: DataCatalogMetricApi[],
                user: UserType | null,
                setupBannerDismissed: boolean
            ): boolean =>
                metricsLoadState === 'loaded' &&
                // The dismissal lives on the user record, so wait for it before showing the banner.
                !!user &&
                allMetrics.length > 0 &&
                allMetrics.length < SMALL_CATALOG_SIZE &&
                !setupBannerDismissed,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        rememberSetupIntent: ({ source }) => {
            const intent: SetupIntent = { teamId: getCurrentTeamId(), source, setAt: Date.now() }
            try {
                sessionStorage.setItem(SETUP_INTENT_KEY, JSON.stringify(intent))
            } catch {
                // Without storage, setup waits for another click after the reauthentication.
            }
        },
        resumeSetupIntent: () => {
            const intent = takeSetupIntent()
            if (intent?.teamId === getCurrentTeamId() && Date.now() - intent.setAt < SETUP_INTENT_TTL_MS) {
                actions.startSetupWithPostHogAI(intent.source)
            }
        },
        watchForNewMetrics: () => {
            // An external agent writes metrics through the MCP server, which sends this page no event.
            // The person comes back to this tab after the agent runs, so reload then, until metrics arrive.
            cache.metricsBaseline = values.allMetrics.length
            cache.disposables.add(() => {
                const onFocus = (): void => actions.loadMetrics()
                window.addEventListener('focus', onFocus)
                return () => window.removeEventListener('focus', onFocus)
            }, 'reloadMetricsOnFocus')
        },
        loadMetricsSuccess: () => {
            if (cache.metricsBaseline !== undefined && values.allMetrics.length > cache.metricsBaseline) {
                cache.metricsBaseline = undefined
                cache.disposables.dispose('reloadMetricsOnFocus')
            }
        },
        startSetupWithPostHogAI: ({ source }) => {
            takeSetupIntent()
            // pinned: analytics event name, renaming it breaks the setup funnel
            posthog.capture('data catalog setup with ai started', { source })
            actions.recordSetupStarted()
            actions.openSidePanel(SidePanelTab.Max, autoRunMaxPrompt(buildPostHogAISetupPrompt()))
        },
        copyAgentSetupPrompt: async ({ source }) => {
            const copied = await copyToClipboard(buildAgentSetupPrompt(values.currentProjectId), 'prompt')
            if (copied) {
                // pinned: analytics event name, renaming it breaks the setup funnel
                posthog.capture('data catalog setup prompt copied', { source })
                actions.recordSetupStarted()
                actions.watchForNewMetrics()
            }
        },
        dismissSetupBanner: () => {
            actions.updateHasSeenProductIntroFor(SETUP_BANNER_DISMISSED_KEY)
            // pinned: analytics event name, renaming it breaks the setup funnel
            posthog.capture('data catalog setup banner dismissed')
        },
        recordSetupStarted: () => {
            if (!values.user?.has_seen_product_intro_for?.[SETUP_STARTED_KEY]) {
                actions.updateHasSeenProductIntroFor(SETUP_STARTED_KEY)
            }
        },
        reportSetupBannerShown: () => {
            // pinned: analytics event name, renaming it breaks the setup funnel
            posthog.capture('data catalog setup banner shown')
        },
    })),
])
