// pinned: key in the user's server-side `has_seen_product_intro_for`, renaming it brings the banner
// back for everyone who dismissed it
export const SETUP_BANNER_DISMISSED_KEY = 'data_catalog_setup_banner'

// pinned: key in the user's server-side `has_seen_product_intro_for`. A person who started setup is not
// asked again, however few metrics the run proposed.
export const SETUP_STARTED_KEY = 'data_catalog_setup_started'

// The app keeps no team-level record of a setup run, so a small catalog stands in for "never set up".
// A setup run seeds metrics from the insights a team uses most, and most catalogs that never had one
// hold only the few metrics an agent proposed while it built a dashboard.
export const SMALL_CATALOG_SIZE = 10

/** Where the person started setup from. pinned: analytics property value, renaming it splits the dashboards */
export type CatalogSetupSource = 'empty_state' | 'banner'

const SETUP_SKILL = 'setting-up-data-catalog'

// Approving AI consent can trigger a full-page SSO reauthentication, which unloads the page before
// `onApprove` runs. The click is stored first, so the setup button can finish it when the page comes back.
// pinned: sessionStorage key
const SETUP_INTENT_KEY = 'data-catalog-setup-with-ai-intent'
const SETUP_INTENT_TTL_MS = 10 * 60 * 1000

interface SetupIntent {
    teamId: number
    source: CatalogSetupSource
    setAt: number
}

function takeSetupIntent(): SetupIntent | null {
    try {
        const stored = sessionStorage.getItem(SETUP_INTENT_KEY)
        sessionStorage.removeItem(SETUP_INTENT_KEY)
        return stored ? (JSON.parse(stored) as SetupIntent) : null
    } catch {
        return null
    }
}

const SETUP_STEPS = [
    `Load the ${SETUP_SKILL} skill first and follow its setup flow.`,
    'Base the metrics on the insights and dashboards this project uses most, and skip any metric the catalog already has.',
    'Leave everything you add as proposed so my team can review it. Do not approve anything.',
    'When you finish, list what you proposed and why.',
]

/**
 * PostHog AI already works in the current project. The empty state replaces the scene, so the
 * scene's attached skill context is absent there, which is why the prompt names the skill itself.
 */
export function buildPostHogAISetupPrompt(): string {
    return ['Set up the data catalog for this project.', ...SETUP_STEPS].join(' ')
}

/** An external agent reaches PostHog through the MCP server and needs the project spelled out. */
export function buildAgentSetupPrompt(projectId: number | null): string {
    const project = projectId ? `PostHog project ${projectId}` : 'my PostHog project'
    return [`Use the PostHog MCP server to set up the data catalog for ${project}.`, ...SETUP_STEPS].join(' ')
}

