import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { copyToClipboard } from 'lib/utils/copyToClipboard'
import { autoRunMaxPrompt } from 'scenes/max/maxPrompt'
import { teamLogic } from 'scenes/teamLogic'
import { userLogic } from 'scenes/userLogic'

import { sidePanelStateLogic } from '~/layout/navigation-3000/sidepanel/sidePanelStateLogic'
import { SidePanelTab, UserType } from '~/types'

import type { DataCatalogMetricApi } from './generated/api.schemas'
import { MetricsLoadState, metricsLogic } from './metricsLogic'

// pinned: key in the user's server-side `has_seen_product_intro_for`, renaming it brings the banner
// back for everyone who dismissed it
export const SETUP_BANNER_DISMISSED_KEY = 'data_catalog_setup_banner'

// The app keeps no record of a setup run, so a small catalog stands in for "never set up". A setup
// run seeds metrics from the insights a team uses most, and most catalogs that never had one hold
// only the few metrics an agent proposed while it built a dashboard.
export const SMALL_CATALOG_SIZE = 10

/** Where the person started setup from. pinned: analytics property value, renaming it splits the dashboards */
export type CatalogSetupSource = 'empty_state' | 'banner'

const SETUP_SKILL = 'setting-up-data-catalog'

const SETUP_STEPS = [
    `Load the ${SETUP_SKILL} skill first and follow its setup flow.`,
    'Base the metrics on the insights and dashboards this project uses most, and skip any metric the catalog already has.',
    'Leave everything you add as proposed so my team can review it. Do not approve anything.',
    'When you finish, list what you proposed and why.',
]

/**
 * PostHog AI already works in the current project. The empty state replaces the scene, so the
 * scene's attached skill context is absent there, which is why the prompt names the skill itself.
 */
export function buildPostHogAISetupPrompt(): string {
    return ['Set up the data catalog for this project.', ...SETUP_STEPS].join(' ')
}

/** An external agent reaches PostHog through the MCP server and needs the project spelled out. */
export function buildAgentSetupPrompt(projectId: number | null): string {
    const project = projectId ? `PostHog project ${projectId}` : 'my PostHog project'
    return [`Use the PostHog MCP server to set up the data catalog for ${project}.`, ...SETUP_STEPS].join(' ')
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface catalogSetupLogicValues {
    allMetrics: DataCatalogMetricApi[] // metricsLogic
    metricsLoadState: MetricsLoadState // metricsLogic
    currentTeamId: number | null // teamLogic
    user: UserType | null // userLogic
    dismissedLocally: boolean
    setupBannerDismissed: boolean
    showSetupBanner: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface catalogSetupLogicActions {
    openSidePanel: (
        tab: SidePanelTab,
        options?: string | undefined
    ) => {
        options: string | undefined
        tab: SidePanelTab
    } // sidePanelStateLogic
    updateHasSeenProductIntroFor: (
        productKey: string,
        value?: boolean | undefined
    ) => {
        productKey: string
        value: boolean
    } // userLogic
    copyAgentSetupPrompt: (source: CatalogSetupSource) => {
        source: CatalogSetupSource
    }
    dismissSetupBanner: () => {
        value: true
    }
    reportSetupBannerShown: () => {
        value: true
    }
    startSetupWithPostHogAI: (source: CatalogSetupSource) => {
        source: CatalogSetupSource
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface catalogSetupLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        setupBannerDismissed: (dismissedLocally: boolean, user: UserType | null) => boolean
        showSetupBanner: (
            metricsLoadState: MetricsLoadState,
            allMetrics: DataCatalogMetricApi[],
            setupBannerDismissed: boolean
        ) => boolean
    }
}

export type catalogSetupLogicType = MakeLogicType<
    catalogSetupLogicValues,
    catalogSetupLogicActions,
    Record<string, any>,
    catalogSetupLogicMeta
>

export const catalogSetupLogic = kea<catalogSetupLogicType>([
    path(['products', 'data_catalog', 'frontend', 'catalogSetupLogic']),
    connect(() => ({
        values: [metricsLogic, ['allMetrics', 'metricsLoadState'], teamLogic, ['currentTeamId'], userLogic, ['user']],
        actions: [sidePanelStateLogic, ['openSidePanel'], userLogic, ['updateHasSeenProductIntroFor']],
    })),
    actions({
        startSetupWithPostHogAI: (source: CatalogSetupSource) => ({ source }),
        copyAgentSetupPrompt: (source: CatalogSetupSource) => ({ source }),
        dismissSetupBanner: true,
        reportSetupBannerShown: true,
    }),
    reducers({
        // Hides the banner at once; the user record confirms the dismissal after it reloads.
        dismissedLocally: [
            false,
            {
                dismissSetupBanner: () => true,
            },
        ],
    }),
    selectors({
        setupBannerDismissed: [
            (s) => [s.dismissedLocally, s.user],
            (dismissedLocally: boolean, user: UserType | null): boolean =>
                dismissedLocally || !!user?.has_seen_product_intro_for?.[SETUP_BANNER_DISMISSED_KEY],
        ],
        showSetupBanner: [
            (s) => [s.metricsLoadState, s.allMetrics, s.setupBannerDismissed],
            (
                metricsLoadState: MetricsLoadState,
                allMetrics: DataCatalogMetricApi[],
                setupBannerDismissed: boolean
            ): boolean =>
                metricsLoadState === 'loaded' &&
                allMetrics.length > 0 &&
                allMetrics.length < SMALL_CATALOG_SIZE &&
                !setupBannerDismissed,
        ],
    }),
    listeners(({ actions, values }) => ({
        startSetupWithPostHogAI: ({ source }) => {
            // pinned: analytics event name, renaming it breaks the setup funnel
            posthog.capture('data catalog setup with ai started', { source })
            actions.openSidePanel(SidePanelTab.Max, autoRunMaxPrompt(buildPostHogAISetupPrompt()))
        },
        copyAgentSetupPrompt: async ({ source }) => {
            const copied = await copyToClipboard(buildAgentSetupPrompt(values.currentTeamId), 'prompt')
            if (copied) {
                // pinned: analytics event name, renaming it breaks the setup funnel
                posthog.capture('data catalog setup prompt copied', { source })
            }
        },
        dismissSetupBanner: () => {
            actions.updateHasSeenProductIntroFor(SETUP_BANNER_DISMISSED_KEY)
            // pinned: analytics event name, renaming it breaks the setup funnel
            posthog.capture('data catalog setup banner dismissed')
        },
        reportSetupBannerShown: () => {
            // pinned: analytics event name, renaming it breaks the setup funnel
            posthog.capture('data catalog setup banner shown')
        },
    })),
])
