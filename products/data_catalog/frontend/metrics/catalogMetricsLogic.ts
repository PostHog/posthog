import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'

import {
    DataQualityOverviewCheckApi,
    DataQualitySubjectHealthApi,
    SubjectTypeEnumApi,
} from 'products/data_quality/frontend/generated/api.schemas'
import {
    SubjectGroup,
    dataQualityOverviewLogic,
    groupChecksBySubject,
} from 'products/data_quality/frontend/overview/dataQualityOverviewLogic'

import { ColumnSort, SortValueGetters, nextColumnSort, sortByColumn } from '../catalogSort'
import { ChecksFilter, checkGroupCounts, matchesChecksFilter, passingShare } from '../catalogTableRows'
import type { DataCatalogMetricApi } from '../generated/api.schemas'
import { metricsLogic } from '../metricsLogic'

export type MetricsSortColumn = 'name' | 'status' | 'checks' | 'owner' | 'updated'
export type MetricsSort = ColumnSort<MetricsSortColumn>

export const DEFAULT_METRICS_SORT: MetricsSort = { column: 'status', direction: 'asc' }
export const DEFAULT_METRIC_CHECKS_FILTER: ChecksFilter = 'any'

const STATUS_RANK: Record<string, number> = { proposed: 0, approved: 1 }

export function metricDisplayName(metric: DataCatalogMetricApi): string {
    return metric.display_name || metric.name
}

export function metricUpdatedAt(metric: DataCatalogMetricApi): string {
    return metric.updated_at ?? metric.created_at
}

function metricSortGetters(
    checkGroupByMetricId: Record<string, SubjectGroup>
): SortValueGetters<DataCatalogMetricApi, MetricsSortColumn> {
    return {
        name: metricDisplayName,
        status: (metric) => STATUS_RANK[metric.status] ?? null,
        checks: (metric) => passingShare(checkGroupCounts(checkGroupByMetricId[metric.id])),
        owner: (metric) => metric.owner || null,
        updated: metricUpdatedAt,
    }
}

