export const catalogMetricsLogic = kea<catalogMetricsLogicType>([
    path(['products', 'data_catalog', 'frontend', 'metrics', 'catalogMetricsLogic']),
    connect(() => ({
        values: [
            metricsLogic,
            ['metrics', 'filters'],
            dataQualityOverviewLogic,
            ['checks', 'healthBySubjectKey'],
            membersLogic,
            ['meFirstMembers'],
        ],
        actions: [membersLogic, ['ensureAllMembersLoaded'], metricsLogic, ['setFilters']],
    })),
    actions({
        toggleSort: (column: MetricsSortColumn) => ({ column }),
        setChecksFilter: (checks: ChecksFilter) => ({ checks }),
        setPage: (list: MetricsListKey, page: number) => ({ list, page }),
        openMetric: (metric: DataCatalogMetricApi) => ({ metric }),
        toggleMetricSelected: (metricId: string) => ({ metricId }),
        setMetricsSelected: (metricIds: string[], selected: boolean) => ({ metricIds, selected }),
        clearMetricSelection: true,
    }),
    reducers({
        sort: [
            DEFAULT_METRICS_SORT as MetricsSort | null,
            {
                toggleSort: (state, { column }) => nextColumnSort(state, column),
            },
        ],
        checksFilter: [
            DEFAULT_METRIC_CHECKS_FILTER as ChecksFilter,
            {
                setChecksFilter: (_, { checks }) => checks,
            },
        ],
        selectedMetricIds: [
            [] as string[],
            {
                toggleMetricSelected: (state, { metricId }) =>
                    state.includes(metricId) ? state.filter((id) => id !== metricId) : [...state, metricId],
                setMetricsSelected: (state, { metricIds, selected }) =>
                    selected ? [...new Set([...state, ...metricIds])] : state.filter((id) => !metricIds.includes(id)),
                clearMetricSelection: () => [],
            },
        ],
        pages: [
            FIRST_PAGES,
            {
                setPage: (state, { list, page }) => ({ ...state, [list]: page }),
                setFilters: () => FIRST_PAGES,
                setChecksFilter: () => FIRST_PAGES,
                toggleSort: () => FIRST_PAGES,
            },
        ],
    }),
    selectors({
        ownerNameByEmail: [
            (s) => [s.meFirstMembers],
            (meFirstMembers: OrganizationMemberType[]): Record<string, string> =>
                Object.fromEntries(meFirstMembers.map((member) => [member.user.email, fullNameOrEmail(member.user)])),
        ],
        checkGroupByMetricId: [
            (s) => [s.checks, s.healthBySubjectKey],
            (
                checks: DataQualityOverviewCheckApi[],
                healthBySubjectKey: Record<string, DataQualitySubjectHealthApi>
            ): Record<string, SubjectGroup> =>
                Object.fromEntries(
                    groupChecksBySubject(checks, healthBySubjectKey)
                        .filter((group) => group.subjectType === SubjectTypeEnumApi.Metric)
                        .map((group) => [group.subjectUuid, group])
                ),
        ],
        checkCountsByMetricId: [
            (s) => [s.metrics, s.checkGroupByMetricId, s.healthBySubjectKey],
            (
                metrics: DataCatalogMetricApi[],
                checkGroupByMetricId: Record<string, SubjectGroup>,
                healthBySubjectKey: Record<string, DataQualitySubjectHealthApi>
            ): Record<string, CheckCounts | null> =>
                Object.fromEntries(
                    metrics.map((metric) => {
                        const group = checkGroupByMetricId[metric.id]
                        const health = healthBySubjectKey[subjectKeyOf(SubjectTypeEnumApi.Metric, metric.id)]
                        return [metric.id, displayedCheckCounts(group, rolledUpCheckCounts(health, group))]
                    })
                ),
        ],
        visibleMetrics: [
            (s) => [s.metrics, s.checkCountsByMetricId, s.ownerNameByEmail, s.checksFilter, s.sort],
            (
                metrics: DataCatalogMetricApi[],
                checkCountsByMetricId: Record<string, CheckCounts | null>,
                ownerNameByEmail: Record<string, string>,
                checksFilter: ChecksFilter,
                sort: MetricsSort | null
            ): DataCatalogMetricApi[] =>
                sortByColumn(
                    metrics.filter((metric) => matchesChecksFilter(!!checkCountsByMetricId[metric.id], checksFilter)),
                    sort,
                    metricSortGetters(checkCountsByMetricId, ownerNameByEmail),
                    metricDisplayName
                ),
        ],
        // The search is not a filter here. It has its own field, and the filter menu does not clear it.
        filtersActive: [
            (s) => [s.filters, s.checksFilter],
            (filters: MetricsFilters, checksFilter: ChecksFilter): boolean =>
                filters.status !== DEFAULT_METRICS_FILTERS.status ||
                filters.createdBy !== null ||
                filters.owner !== null ||
                checksFilter !== DEFAULT_METRIC_CHECKS_FILTER,
        ],
        metricLists: [
            (s) => [s.visibleMetrics],
            (visibleMetrics: DataCatalogMetricApi[]): Record<MetricsListKey, DataCatalogMetricApi[]> => ({
                all: visibleMetrics,
                proposed: visibleMetrics.filter((metric) => metric.status === 'proposed'),
                // The second list takes each status that is not proposed, so no metric is absent from the two lists.
                approved: visibleMetrics.filter((metric) => metric.status !== 'proposed'),
            }),
        ],
        listPages: [
            (s) => [s.metricLists, s.pages],
            (
                metricLists: Record<MetricsListKey, DataCatalogMetricApi[]>,
                pages: Record<MetricsListKey, number>
            ): Record<MetricsListKey, MetricsListPage> => ({
                all: listPage(metricLists.all, pages.all, LIST_PAGE_SIZES.all),
                proposed: listPage(metricLists.proposed, pages.proposed, LIST_PAGE_SIZES.proposed),
                approved: listPage(metricLists.approved, pages.approved, LIST_PAGE_SIZES.approved),
            }),
        ],
    }),
    listeners({
        openMetric: ({ metric }) => {
            router.actions.push(urls.dataCatalogMetric(metric.name))
        },
    }),
    afterMount(({ actions }) => {
        actions.ensureAllMembersLoaded()
    }),
])
