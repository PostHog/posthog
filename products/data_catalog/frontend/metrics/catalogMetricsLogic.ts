export const catalogMetricsLogic = kea<catalogMetricsLogicType>([
    path(['products', 'data_catalog', 'frontend', 'metrics', 'catalogMetricsLogic']),
    connect(() => ({
        values: [
            metricsLogic,
            ['metrics'],
            dataQualityOverviewLogic,
            ['checks', 'healthBySubjectKey'],
            membersLogic,
            ['meFirstMembers'],
        ],
        actions: [membersLogic, ['ensureAllMembersLoaded'], metricsLogic, ['setFilters']],
    })),
    actions(({ values }) => ({
        toggleSort: (column: MetricsSortColumn) => ({ column }),
        setChecksFilter: (checks: ChecksFilter) => ({ checks }),
        setPage: (page: number) => ({ page }),
        toggleMetricExpanded: (metricId: string) => ({
            metricId,
            expandable: !!values.checkGroupByMetricId[metricId],
        }),
        toggleMetricSelected: (metricId: string) => ({ metricId }),
        setMetricsSelected: (metricIds: string[], selected: boolean) => ({ metricIds, selected }),
        clearMetricSelection: true,
    })),
    reducers({
        sort: [
            DEFAULT_METRICS_SORT as MetricsSort | null,
            {
                toggleSort: (state, { column }) => nextColumnSort(state, column),
            },
        ],
        checksFilter: [
            DEFAULT_METRIC_CHECKS_FILTER as ChecksFilter,
            {
                setChecksFilter: (_, { checks }) => checks,
            },
        ],
        expandedMetricIds: [
            [] as string[],
            {
                toggleMetricExpanded: (state, { metricId, expandable }) => {
                    if (state.includes(metricId)) {
                        return state.filter((id) => id !== metricId)
                    }
                    return expandable ? [...state, metricId] : state
                },
            },
        ],
        selectedMetricIds: [
            [] as string[],
            {
                toggleMetricSelected: (state, { metricId }) =>
                    state.includes(metricId) ? state.filter((id) => id !== metricId) : [...state, metricId],
                setMetricsSelected: (state, { metricIds, selected }) =>
                    selected ? [...new Set([...state, ...metricIds])] : state.filter((id) => !metricIds.includes(id)),
                clearMetricSelection: () => [],
            },
        ],
        page: [
            1,
            {
                setPage: (_, { page }) => page,
                setFilters: () => 1,
                setChecksFilter: () => 1,
                toggleSort: () => 1,
            },
        ],
    }),
    selectors({
        ownerNameByEmail: [
            (s) => [s.meFirstMembers],
            (meFirstMembers: OrganizationMemberType[]): Record<string, string> =>
                Object.fromEntries(meFirstMembers.map((member) => [member.user.email, fullNameOrEmail(member.user)])),
        ],
        checkGroupByMetricId: [
            (s) => [s.checks, s.healthBySubjectKey],
            (
                checks: DataQualityOverviewCheckApi[],
                healthBySubjectKey: Record<string, DataQualitySubjectHealthApi>
            ): Record<string, SubjectGroup> =>
                Object.fromEntries(
                    groupChecksBySubject(checks, healthBySubjectKey)
                        .filter((group) => group.subjectType === SubjectTypeEnumApi.Metric)
                        .map((group) => [group.subjectUuid, group])
                ),
        ],
        visibleMetrics: [
            (s) => [s.metrics, s.checkGroupByMetricId, s.ownerNameByEmail, s.checksFilter, s.sort],
            (
                metrics: DataCatalogMetricApi[],
                checkGroupByMetricId: Record<string, SubjectGroup>,
                ownerNameByEmail: Record<string, string>,
                checksFilter: ChecksFilter,
                sort: MetricsSort | null
            ): DataCatalogMetricApi[] =>
                sortByColumn(
                    metrics.filter((metric) => matchesChecksFilter(!!checkGroupByMetricId[metric.id], checksFilter)),
                    sort,
                    metricSortGetters(checkGroupByMetricId, ownerNameByEmail),
                    metricDisplayName
                ),
        ],
        pageCount: [
            (s) => [s.visibleMetrics],
            (visibleMetrics: DataCatalogMetricApi[]): number => pageCountFor(visibleMetrics.length),
        ],
        currentPage: [
            (s) => [s.page, s.pageCount],
            (page: number, pageCount: number): number => Math.min(page, pageCount),
        ],
        pageMetrics: [
            (s) => [s.visibleMetrics, s.currentPage],
            (visibleMetrics: DataCatalogMetricApi[], currentPage: number): DataCatalogMetricApi[] =>
                itemsOnPage(visibleMetrics, currentPage),
        ],
    }),
    afterMount(({ actions }) => {
        actions.ensureAllMembersLoaded()
    }),
])
