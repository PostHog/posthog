import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, selectors } from 'kea'
import { router, urlToAction } from 'kea-router'
import posthog from 'posthog-js'

import { createFuse } from 'lib/utils/fuseSearch'
import { urls } from 'scenes/urls'

import { SUGGESTED_METRICS_FILTER, TABLES_FILTER_PARAM } from '../catalogTableRows'
import type { ChecksFilter } from '../catalogTableRows'
import { DEFAULT_METRICS_FILTERS, metricsLogic } from '../metricsLogic'
import type { MetricsFilters } from '../metricsLogic'
import type { ProposedRow } from '../proposedRows'
import { usageLogic } from '../usageLogic'
import type { LatestScan } from '../usageLogic'
import { DEFAULT_METRIC_CHECKS_FILTER, catalogMetricsLogic } from './catalogMetricsLogic'

// pinned: analytics event name and properties, renaming breaks the insights built on them
const SUGGESTED_METRICS_SHOWN_EVENT = 'data catalog suggested metrics shown'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface catalogSuggestedMetricsLogicValues {
    filtersActive: boolean // catalogMetricsLogic
    filters: MetricsFilters // metricsLogic
    proposedRows: ProposedRow[] // usageLogic
    visibleSuggestions: ProposedRow[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface catalogSuggestedMetricsLogicActions {
    setChecksFilter: (checks: ChecksFilter) => {
        checks: ChecksFilter
    } // catalogMetricsLogic
    setFilters: (filters: Partial<MetricsFilters>) => {
        filters: Partial<MetricsFilters>
    } // metricsLogic
    loadLatestSuccess: (
        latest: LatestScan,
        payload?: any
    ) => {
        latest: LatestScan
        payload?: any
    } // usageLogic
    reportSuggestionsShown: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface catalogSuggestedMetricsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        visibleSuggestions: (
            proposedRows: ProposedRow[],
            filters: MetricsFilters,
            filtersActive: boolean
        ) => ProposedRow[]
    }
}

export type catalogSuggestedMetricsLogicType = MakeLogicType<
    catalogSuggestedMetricsLogicValues,
    catalogSuggestedMetricsLogicActions,
    Record<string, any>,
    catalogSuggestedMetricsLogicMeta
>

export const catalogSuggestedMetricsLogic = kea<catalogSuggestedMetricsLogicType>([
    path(['products', 'data_catalog', 'frontend', 'metrics', 'catalogSuggestedMetricsLogic']),
    connect(() => ({
        values: [usageLogic, ['proposedRows'], metricsLogic, ['filters'], catalogMetricsLogic, ['filtersActive']],
        actions: [
            usageLogic,
            ['loadLatestSuccess'],
            metricsLogic,
            ['setFilters'],
            catalogMetricsLogic,
            ['setChecksFilter'],
        ],
    })),
    actions({
        reportSuggestionsShown: true,
    }),
    selectors({
        visibleSuggestions: [
            (s) => [s.proposedRows, s.filters, s.filtersActive],
            (proposedRows: ProposedRow[], filters: MetricsFilters, filtersActive: boolean): ProposedRow[] => {
                // A suggestion has no status, owner, creator or checks, so it matches none of the filters.
                if (filtersActive) {
                    return []
                }
                if (!filters.search) {
                    return proposedRows
                }
                return createFuse<ProposedRow>(proposedRows, {
                    keys: ['name', 'measure', 'description'],
                    threshold: 0.3,
                })
                    .search(filters.search)
                    .map((result) => result.item)
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadLatestSuccess: () => actions.reportSuggestionsShown(),
        // A change to the search or to a filter can bring hidden suggestions onto the page.
        setFilters: () => actions.reportSuggestionsShown(),
        setChecksFilter: () => actions.reportSuggestionsShown(),
        reportSuggestionsShown: () => {
            // The scan loads again after a rescan. One report for each visit keeps the count equal to the visits.
            // A visit that shows no suggestion, because the search or a filter hides each one, gets no report.
            if (cache.shownReported || values.visibleSuggestions.length === 0) {
                return
            }
            cache.shownReported = true
            posthog.capture(SUGGESTED_METRICS_SHOWN_EVENT, { count: values.proposedRows.length })
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.dataCatalog()]: (_, searchParams, hashParams) => {
            if (searchParams.tab !== 'metrics' || searchParams[TABLES_FILTER_PARAM] !== SUGGESTED_METRICS_FILTER) {
                return
            }
            // The Metrics tab keeps its search and its filters between visits, and they can hide each suggestion.
            if (values.filters.search || values.filtersActive) {
                actions.setFilters(DEFAULT_METRICS_FILTERS)
                actions.setChecksFilter(DEFAULT_METRIC_CHECKS_FILTER)
            }
            router.actions.replace(
                urls.dataCatalog(),
                { ...searchParams, [TABLES_FILTER_PARAM]: undefined },
                hashParams
            )
        },
    })),
    // The Overview can load the scan before this tab opens, and no load event comes then.
    afterMount(({ actions }) => actions.reportSuggestionsShown()),
])
