export const TABLES_PAGE_SIZE = 20

const TRUST_URL_FILTERS: TrustFilter[] = ['proposed', 'certified', 'deprecated']
const ATTENTION_URL_FILTER = 'attention'

function projectId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

function isTrustUrlFilter(value: unknown): value is TrustFilter {
    return TRUST_URL_FILTERS.includes(value as TrustFilter)
}

