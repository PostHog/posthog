export const TABLES_PAGE_SIZE = 20

export type TablesBulkAction = ProposalDecision | 'certify'

const CERTIFIED_STATUS = 'certified'

interface CertificationChange {
    updated?: DataCatalogCertificationApi
    removedId?: string
}

const PROPOSAL_REVIEW_EVENTS: Record<ProposalDecision, string> = {
    accept: 'data catalog proposal accepted',
    reject: 'data catalog proposal rejected',
}

const TRUST_URL_FILTERS: TrustFilter[] = ['proposed', 'certified', 'deprecated']
const ATTENTION_URL_FILTER = 'attention'

function singleReviewMessage(row: CatalogTableRow, decision: ProposalDecision): string {
    if (decision === 'reject') {
        return `Rejected the proposal for ${row.name}`
    }
    return `${row.certification && proposalAcceptsAsDeprecation(row.certification) ? 'Deprecated' : 'Certified'} ${row.name}`
}

function projectId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

function isTrustUrlFilter(value: unknown): value is TrustFilter {
    return TRUST_URL_FILTERS.includes(value as TrustFilter)
}

