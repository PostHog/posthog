export const catalogTablesLogic = kea<catalogTablesLogicType>([
    path(['products', 'data_catalog', 'frontend', 'catalogTablesLogic']),
    connect(() => ({
        values: [
            databaseTableListLogic,
            ['posthogTables', 'dataWarehouseTables', 'views', 'database', 'databaseLoadError'],
            dataQualityOverviewLogic,
            ['checks', 'healthBySubjectKey', 'snapshotLoaded', 'overviewError'],
            certificationsLogic,
            ['certifications'],
            lineageDataLogic,
            ['nodes'],
            modelsOverviewLogic,
            ['materializationProblems', 'modelsKnown', 'modelsFailed'],
            viewsTabLogic,
            ['enrichedViews'],
        ],
        actions: [
            databaseTableListLogic,
            ['loadDatabase', 'loadDatabaseSuccess'],
            dataWarehouseViewsLogic,
            ['loadDataWarehouseSavedQueriesSuccess'],
            dataQualityOverviewLogic,
            ['runChecks'],
            certificationsLogic,
            ['openNewCertificationModal', 'setNewCertificationForm', 'loadCertificationsSuccess'],
            viewsTabLogic,
            ['loadRunHistory'],
        ],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setScope: (scope: TableScope) => ({ scope }),
        setFilters: (filters: Partial<TablesFilters>) => ({ filters }),
        clearFilters: true,
        setPage: (page: number) => ({ page }),
        loadVisibleRunHistory: true,
        toggleRowExpanded: (rowKey: string) => ({ rowKey }),
        runTableChecks: (row: CatalogTableRow) => ({ row }),
        proposeCertification: (row: CatalogTableRow) => ({ row }),
        revealCertification: (certificationId: string) => ({ certificationId }),
        clearPendingReveal: true,
    }),
    loaders(() => ({
        posthogTableSubjectIds: [
            {} as Record<string, string>,
            {
                loadPosthogTableSubjectIds: async (): Promise<Record<string, string>> => {
                    const subjects = await dataQualityChecksSubjectsList(projectId(), {
                        subject_type: SubjectTypeEnumApi.PosthogTable,
                        include_columns: false,
                    })
                    return Object.fromEntries(subjects.map((subject) => [subject.name, subject.id]))
                },
            },
        ],
    })),
    reducers({
        search: [
            '',
            {
                setSearch: (_, { search }) => search,
            },
        ],
        scope: [
            'all' as TableScope,
            {
                setScope: (_, { scope }) => scope,
            },
        ],
        filters: [
            DEFAULT_TABLES_FILTERS,
            {
                setFilters: (state, { filters }) => ({ ...state, ...filters }),
                clearFilters: () => DEFAULT_TABLES_FILTERS,
            },
        ],
        page: [
            1,
            {
                setPage: (_, { page }) => page,
                setSearch: () => 1,
                setScope: () => 1,
                setFilters: () => 1,
                clearFilters: () => 1,
            },
        ],
        expandedRowKeys: [
            [] as string[],
            {
                toggleRowExpanded: (state, { rowKey }) =>
                    state.includes(rowKey) ? state.filter((key) => key !== rowKey) : [...state, rowKey],
                runTableChecks: (state, { row }) => (state.includes(row.key) ? state : [...state, row.key]),
            },
        ],
        pendingRevealCertificationId: [
            null as string | null,
            {
                revealCertification: (_, { certificationId }) => certificationId,
                clearPendingReveal: () => null,
            },
        ],
    }),
    selectors({
        rows: [
            (s) => [
                s.posthogTables,
                s.dataWarehouseTables,
                s.views,
                s.enrichedViews,
                s.checks,
                s.healthBySubjectKey,
                s.certifications,
                s.nodes,
                s.materializationProblems,
                s.posthogTableSubjectIds,
            ],
            (
                posthogTables: DatabaseSchemaTable[],
                dataWarehouseTables: DatabaseSchemaDataWarehouseTable[],
                views: DatabaseSchemaViewTable[],
                enrichedViews: DataWarehouseSavedQuerySummary[],
                checks: DataQualityOverviewCheckApi[],
                healthBySubjectKey: Record<string, DataQualitySubjectHealthApi>,
                certifications: DataCatalogCertificationApi[],
                nodes: DataModelingNode[],
                materializationProblems: MaterializationProblem[],
                posthogTableSubjectIds: Record<string, string>
            ): CatalogTableRow[] =>
                buildCatalogTableRows({
                    posthogTables,
                    dataWarehouseTables,
                    views,
                    savedQueries: enrichedViews,
                    checkGroups: groupChecksBySubject(checks, healthBySubjectKey),
                    certifications,
                    nodes,
                    materializationProblems,
                    posthogTableSubjectIds,
                }),
        ],
        rowsLoaded: [
            (s) => [s.database, s.snapshotLoaded, s.modelsKnown],
            (database: DatabaseSchemaQueryResponse | null, snapshotLoaded: boolean, modelsKnown: boolean): boolean =>
                !!database && snapshotLoaded && modelsKnown,
        ],
        rowsError: [
            (s) => [s.database, s.databaseLoadError, s.snapshotLoaded, s.overviewError],
            (
                database: DatabaseSchemaQueryResponse | null,
                databaseLoadError: string | null,
                snapshotLoaded: boolean,
                overviewError: string | null
            ): string | null => (!database && databaseLoadError) || (!snapshotLoaded && overviewError) || null,
        ],
        filtersActive: [
            (s) => [s.filters],
            (filters: TablesFilters): boolean => !objectsEqual(filters, DEFAULT_TABLES_FILTERS),
        ],
        searchedRows: [
            (s) => [s.rows, s.filters, s.search],
            (rows: CatalogTableRow[], filters: TablesFilters, search: string): CatalogTableRow[] =>
                rows.filter((row) => rowMatchesFilters(row, filters) && rowMatchesSearch(row, search)),
        ],
        scopeCounts: [
            (s) => [s.searchedRows],
            (searchedRows: CatalogTableRow[]): Record<TableScope, number> => ({
                all: searchedRows.length,
                attention: searchedRows.filter(rowNeedsAttention).length,
            }),
        ],
        filteredRows: [
            (s) => [s.searchedRows, s.scope],
            (searchedRows: CatalogTableRow[], scope: TableScope): CatalogTableRow[] =>
                scope === 'attention' ? searchedRows.filter(rowNeedsAttention) : searchedRows,
        ],
        pageCount: [
            (s) => [s.filteredRows],
            (filteredRows: CatalogTableRow[]): number => Math.max(1, Math.ceil(filteredRows.length / TABLES_PAGE_SIZE)),
        ],
        currentPage: [
            (s) => [s.page, s.pageCount],
            (page: number, pageCount: number): number => Math.min(page, pageCount),
        ],
        visibleRows: [
            (s) => [s.filteredRows, s.currentPage],
            (filteredRows: CatalogTableRow[], currentPage: number): CatalogTableRow[] => {
                const start = (currentPage - 1) * TABLES_PAGE_SIZE
                return filteredRows.slice(start, start + TABLES_PAGE_SIZE)
            },
        ],
    }),
    listeners(({ actions, values }) => {
        const revealIfLoaded = (): void => {
            const certification = values.certifications.find(
                (candidate) => candidate.id === values.pendingRevealCertificationId
            )
            if (!certification) {
                return
            }
            actions.clearFilters()
            actions.setScope('all')
            actions.setSearch(certification.target_name)
            actions.clearPendingReveal()
        }
        const loadVisibleRunHistory = (): void => actions.loadVisibleRunHistory()

        return {
            loadVisibleRunHistory: () => {
                const materializedIds = values.visibleRows.flatMap((row) =>
                    row.kind === 'materialized_view' && row.savedQuery ? [row.savedQuery.id] : []
                )
                if (materializedIds.length > 0) {
                    actions.loadRunHistory(materializedIds)
                }
            },
            setPage: loadVisibleRunHistory,
            setSearch: loadVisibleRunHistory,
            setScope: loadVisibleRunHistory,
            setFilters: loadVisibleRunHistory,
            clearFilters: loadVisibleRunHistory,
            loadDataWarehouseSavedQueriesSuccess: loadVisibleRunHistory,
            loadDatabaseSuccess: loadVisibleRunHistory,
            runTableChecks: ({ row }) => {
                if (!row.checkGroup) {
                    return
                }
                actions.runChecks(
                    { kind: 'subject', subjectKey: row.checkGroup.subjectKey },
                    row.checkGroup.checks.map((check) => check.id)
                )
            },
            proposeCertification: ({ row }) => {
                if (!row.certificationTarget) {
                    return
                }
                actions.openNewCertificationModal()
                actions.setNewCertificationForm({
                    targetId: row.certificationTarget.targetId,
                    targetType: row.certificationTarget.targetType,
                    targetName: row.name,
                })
            },
            revealCertification: revealIfLoaded,
            loadCertificationsSuccess: revealIfLoaded,
        }
    }),
    urlToAction(({ actions }) => ({
        [urls.dataCatalog()]: (_, searchParams, hashParams) => {
            const filter = searchParams[TABLES_FILTER_PARAM]
            const table = searchParams[TABLES_SEARCH_PARAM]
            if (filter === undefined && table === undefined) {
                return
            }
            if (isTrustUrlFilter(filter)) {
                actions.setFilters({ trust: filter })
            }
            if (filter === ATTENTION_URL_FILTER) {
                actions.setScope('attention')
            }
            if (typeof table === 'string') {
                actions.setSearch(table)
            }
            router.actions.replace(
                urls.dataCatalog(),
                { ...searchParams, [TABLES_FILTER_PARAM]: undefined, [TABLES_SEARCH_PARAM]: undefined },
                hashParams
            )
        },
    })),
    afterMount(({ actions, values }) => {
        if (!values.database) {
            actions.loadDatabase()
        }
        actions.loadPosthogTableSubjectIds()
        actions.loadVisibleRunHistory()
    }),
])
