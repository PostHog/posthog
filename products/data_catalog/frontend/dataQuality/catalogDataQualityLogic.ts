export const catalogDataQualityLogic = kea<catalogDataQualityLogicType>([
    path(['products', 'data_catalog', 'frontend', 'dataQuality', 'catalogDataQualityLogic']),
    connect(() => ({
        values: [catalogTablesLogic, ['rows', 'checkGroups', 'rowsLoaded', 'rowsError'], router, ['searchParams']],
        actions: [dataQualityOverviewLogic, ['runChecks']],
    })),
    actions({
        toggleTableExpanded: (rowKey: string) => ({ rowKey }),
        runTableChecks: (row: ChecksSubject) => ({ row }),
        showAllTables: true,
        setSearch: (search: string) => ({ search }),
        setScope: (scope: ChecksScope) => ({ scope }),
        clearFilters: true,
    }),
    reducers({
        search: [
            '',
            {
                setSearch: (_, { search }) => search,
                clearFilters: () => '',
            },
        ],
        scope: [
            'all' as ChecksScope,
            {
                setScope: (_, { scope }) => scope,
                clearFilters: () => 'all',
            },
        ],
        expandedTableKeys: [
            [] as string[],
            {
                toggleTableExpanded: (state, { rowKey }) =>
                    state.includes(rowKey) ? state.filter((key) => key !== rowKey) : [...state, rowKey],
                runTableChecks: (state, { row }) => (state.includes(row.key) ? state : [...state, row.key]),
            },
        ],
    }),
    selectors({
        tableFilter: [
            (s) => [s.searchParams],
            (searchParams: Record<string, any>): string | null => {
                const table = searchParams[TABLES_SEARCH_PARAM]
                return searchParams.tab === DATA_QUALITY_TAB && typeof table === 'string' ? table : null
            },
        ],
        checkedRows: [
            (s) => [s.rows, s.checkGroups, s.tableFilter],
            (rows: CatalogTableRow[], checkGroups: SubjectGroup[], tableFilter: string | null): ChecksSubject[] => {
                const listedGroupKeys = new Set(
                    rows.flatMap((row) => (row.checkGroup ? [row.checkGroup.subjectKey] : []))
                )
                const unlisted = checkGroups
                    .filter((group) => !listedGroupKeys.has(group.subjectKey))
                    .map(checksSubjectOf)
                if (tableFilter) {
                    return [...rows, ...unlisted].filter((subject) => subject.name === tableFilter)
                }
                return [...rows.filter((row) => row.checkGroup), ...unlisted]
            },
        ],
        searchedRows: [
            (s) => [s.checkedRows, s.search, s.tableFilter],
            (checkedRows: ChecksSubject[], search: string, tableFilter: string | null): ChecksSubject[] =>
                tableFilter ? checkedRows : checkedRows.filter((row) => subjectMatchesSearch(row, search)),
        ],
        scopeCounts: [
            (s) => [s.searchedRows],
            (searchedRows: ChecksSubject[]): Record<ChecksScope, number> => ({
                all: searchedRows.length,
                failing: searchedRows.filter(subjectHasFailingChecks).length,
            }),
        ],
        shownRows: [
            (s) => [s.searchedRows, s.scope, s.tableFilter],
            (searchedRows: ChecksSubject[], scope: ChecksScope, tableFilter: string | null): ChecksSubject[] =>
                tableFilter || scope === 'all' ? searchedRows : searchedRows.filter(subjectHasFailingChecks),
        ],
    }),
    listeners(({ actions, values }) => ({
        runTableChecks: ({ row }) => {
            if (!row.checkGroup) {
                return
            }
            actions.runChecks(
                { kind: 'subject', subjectKey: row.checkGroup.subjectKey },
                row.checkGroup.checks.map((check) => check.id)
            )
        },
        showAllTables: () => {
            router.actions.replace(urls.dataCatalog(), { ...values.searchParams, [TABLES_SEARCH_PARAM]: undefined })
        },
    })),
])
