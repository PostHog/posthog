import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { userLogic } from 'scenes/userLogic'

import { UserType } from '~/types'

import { catalogSetupLogic } from './catalogSetupLogic'
import type { DataCatalogMetricApi } from './generated/api.schemas'
import { MetricsLoadState, metricsLogic } from './metricsLogic'

// pinned: key in the user's server-side `has_seen_product_intro_for`, renaming it shows the intro
// again to everyone who saw it
export const METRICS_INTRO_SEEN_KEY = 'data_catalog_metrics_intro'

/** Where the person saw how metrics work. pinned: analytics property value */
export type MetricsIntroSurface = 'empty_state' | 'strip'

export type MetricsNotice = 'intro' | 'setup' | null

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsIntroLogicValues {
    showSetupBanner: boolean // catalogSetupLogic
    allMetrics: DataCatalogMetricApi[] // metricsLogic
    metricsLoadState: MetricsLoadState // metricsLogic
    user: UserType | null // userLogic
    dismissedLocally: boolean
    metricsNotice: MetricsNotice
    seenBefore: boolean
    showIntroStrip: boolean
    stripShownThisVisit: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsIntroLogicActions {
    updateHasSeenProductIntroFor: (
        productKey: string,
        value?: boolean | undefined
    ) => {
        productKey: string
        value: boolean
    } // userLogic
    dismissIntro: () => {
        value: true
    }
    reportIntroShown: (surface: MetricsIntroSurface) => {
        surface: MetricsIntroSurface
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsIntroLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        seenBefore: (user: UserType | null) => boolean
        showIntroStrip: (
            metricsLoadState: MetricsLoadState,
            allMetrics: DataCatalogMetricApi[],
            user: UserType | null,
            seenBefore: boolean,
            stripShownThisVisit: any,
            dismissedLocally: boolean
        ) => boolean
        metricsNotice: (showIntroStrip: boolean, stripShownThisVisit: any, showSetupBanner: any) => MetricsNotice
    }
}

export type metricsIntroLogicType = MakeLogicType<
    metricsIntroLogicValues,
    metricsIntroLogicActions,
    Record<string, any>,
    metricsIntroLogicMeta
>

export const metricsIntroLogic = kea<metricsIntroLogicType>([
    path(['products', 'data_catalog', 'frontend', 'metricsIntroLogic']),
    connect(() => ({
        values: [
            metricsLogic,
            ['allMetrics', 'metricsLoadState'],
            userLogic,
            ['user'],
            catalogSetupLogic,
            ['showSetupBanner'],
        ],
        actions: [userLogic, ['updateHasSeenProductIntroFor']],
    })),
    actions({
        reportIntroShown: (surface: MetricsIntroSurface) => ({ surface }),
        dismissIntro: true,
    }),
    reducers({
        // The strip that records the intro as seen stays on screen until the person leaves the page,
        // because the user record says "seen" again as soon as it reloads. The empty-state diagram
        // does not count: once metrics arrive, the table replaces it and the strip would repeat it.
        stripShownThisVisit: [
            false,
            {
                reportIntroShown: (state, { surface }) => state || surface === 'strip',
            },
        ],
        dismissedLocally: [
            false,
            {
                dismissIntro: () => true,
            },
        ],
    }),
    selectors({
        seenBefore: [
            (s) => [s.user],
            (user: UserType | null): boolean => !!user?.has_seen_product_intro_for?.[METRICS_INTRO_SEEN_KEY],
        ],
        showIntroStrip: [
            (s) => [s.metricsLoadState, s.allMetrics, s.user, s.seenBefore, s.stripShownThisVisit, s.dismissedLocally],
            (
                metricsLoadState: MetricsLoadState,
                allMetrics: DataCatalogMetricApi[],
                user: UserType | null,
                seenBefore: boolean,
                stripShownThisVisit: boolean,
                dismissedLocally: boolean
            ): boolean =>
                metricsLoadState === 'loaded' &&
                // Until the user record loads, a returning person would look like a first visit.
                !!user &&
                // An empty catalog shows the full diagram in its empty state instead.
                allMetrics.length > 0 &&
                !dismissedLocally &&
                (!seenBefore || stripShownThisVisit),
        ],
        /** One notice at a time: the intro on a first visit, the setup offer on a later visit. */
        metricsNotice: [
            (s) => [s.showIntroStrip, s.stripShownThisVisit, s.showSetupBanner],
            (showIntroStrip: boolean, stripShownThisVisit: boolean, showSetupBanner: boolean): MetricsNotice => {
                if (showIntroStrip) {
                    return 'intro'
                }
                // A person who closes the intro does not get a second notice in its place on the same visit.
                return showSetupBanner && !stripShownThisVisit ? 'setup' : null
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        reportIntroShown: ({ surface }) => {
            // The empty state can mount again before the user record reloads, so send the write once.
            if (!values.seenBefore && !cache.seenRequested) {
                cache.seenRequested = true
                actions.updateHasSeenProductIntroFor(METRICS_INTRO_SEEN_KEY)
            }
            // pinned: analytics event name
            posthog.capture('data catalog metrics intro shown', { surface })
        },
        dismissIntro: () => {
            // pinned: analytics event name
            posthog.capture('data catalog metrics intro dismissed')
        },
    })),
])
