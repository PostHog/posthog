import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { router } from 'kea-router'

import { resolveToolCall, toolStreamEventsLogic } from 'products/posthog_ai/frontend/api/logics'
import type { ToolStreamEvent } from 'products/posthog_ai/frontend/api/types'

import { certificationsLogic } from './certificationsLogic'
import { validateMetricName } from './common'
import { metricsLogic } from './metricsLogic'
import { relationshipsLogic } from './relationshipsLogic'

export const METRIC_TOOLS = [
    'data-catalog-metric-create',
    'data-catalog-metric-update',
    'data-catalog-metric-approve-execute',
    'data-catalog-metrics-refresh-from-insight-create',
]
export const RELATIONSHIP_TOOLS = [
    'data-catalog-relationship-propose',
    'data-catalog-relationship-accept-execute',
    'data-catalog-relationship-reject-execute',
]
export const CERTIFICATION_TOOLS = [
    'data-catalog-certification-propose',
    'data-catalog-certification-certify-execute',
    'data-catalog-certification-deprecate-execute',
]
export const READ_TOOLS = ['data-catalog-metric-run', 'metric-list', 'metric-describe']
export const TOOL_RELOAD_DEBOUNCE_MS = 300

const LISTENER_ID = 'data-catalog-agent-sync'
const SUBSCRIBED_TOOLS = [...METRIC_TOOLS, ...RELATIONSHIP_TOOLS, ...CERTIFICATION_TOOLS]

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataCatalogAgentSyncLogicValues {
    openMetricName: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataCatalogAgentSyncLogicActions {
    certificationsChanged: (toolName: string) => {
        toolName: string
    }
    metricsChanged: () => {
        value: true
    }
    openMetricChanged: (
        toolName: string,
        innerInput: Record<string, unknown> | undefined
    ) => {
        innerInput: Record<string, unknown> | undefined
        toolName: string
    }
    openMetricReloadRequested: (
        name: string,
        newName?: string
    ) => {
        name: string
        newName: string | undefined
    }
    relationshipsChanged: (toolName: string) => {
        toolName: string
    }
    setOpenMetricName: (name: string | null) => {
        name: string | null
    }
    toolCompleted: (event: ToolStreamEvent) => {
        event: ToolStreamEvent
    }
}

export type dataCatalogAgentSyncLogicType = MakeLogicType<
    dataCatalogAgentSyncLogicValues,
    dataCatalogAgentSyncLogicActions
>

export const dataCatalogAgentSyncLogic = kea<dataCatalogAgentSyncLogicType>([
    path(['products', 'data_catalog', 'frontend', 'dataCatalogAgentSyncLogic']),
    connect([toolStreamEventsLogic]),
    actions({
        toolCompleted: (event: ToolStreamEvent) => ({ event }),
        metricsChanged: true,
        certificationsChanged: (toolName: string) => ({ toolName }),
        relationshipsChanged: (toolName: string) => ({ toolName }),
        openMetricChanged: (toolName: string, innerInput: Record<string, unknown> | undefined) => ({
            toolName,
            innerInput,
        }),
        openMetricReloadRequested: (name: string, newName?: string) => ({ name, newName }),
        setOpenMetricName: (name: string | null) => ({ name }),
    }),
    reducers({
        openMetricName: [
            null as string | null,
            {
                setOpenMetricName: (_, { name }) => name,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        toolCompleted: ({ event }) => {
            if (event.phase !== 'completed') {
                return
            }

            const { toolName } = event
            const innerInput = resolveToolCall(event.invocation).innerInput
            if (METRIC_TOOLS.includes(toolName)) {
                actions.metricsChanged()
                actions.openMetricChanged(toolName, innerInput)
                return
            }
            if (CERTIFICATION_TOOLS.includes(toolName)) {
                actions.certificationsChanged(toolName)
                return
            }
            if (RELATIONSHIP_TOOLS.includes(toolName)) {
                actions.relationshipsChanged(toolName)
                return
            }
        },
        metricsChanged: async (_, breakpoint) => {
            await breakpoint(TOOL_RELOAD_DEBOUNCE_MS)
            if (metricsLogic.isMounted()) {
                metricsLogic.actions.loadMetrics()
            }
        },
        certificationsChanged: async ({ toolName }, breakpoint) => {
            await breakpoint(TOOL_RELOAD_DEBOUNCE_MS)
            if (!certificationsLogic.isMounted()) {
                return
            }
            certificationsLogic.actions.loadCertifications()
            if (
                toolName === 'data-catalog-certification-certify-execute' ||
                toolName === 'data-catalog-certification-deprecate-execute'
            ) {
                certificationsLogic.actions.loadDatabase({ force: true })
            }
        },
        relationshipsChanged: async ({ toolName }, breakpoint) => {
            await breakpoint(TOOL_RELOAD_DEBOUNCE_MS)
            if (!relationshipsLogic.isMounted()) {
                return
            }
            relationshipsLogic.actions.loadPendingCount()
            if (router.values.searchParams.tab !== 'relationships') {
                return
            }
            relationshipsLogic.actions.loadProposals()
            if (toolName === 'data-catalog-relationship-accept-execute') {
                relationshipsLogic.actions.loadJoins()
            }
        },
        openMetricChanged: ({ toolName, innerInput }) => {
            const targetName = typeof innerInput?.name === 'string' ? innerInput.name : null
            const openMetricName = values.openMetricName
            if (!openMetricName || (targetName && targetName !== openMetricName)) {
                return
            }

            const newName = typeof innerInput?.new_name === 'string' ? innerInput.new_name : null
            if (
                toolName === 'data-catalog-metric-update' &&
                newName &&
                newName !== openMetricName &&
                !validateMetricName(newName)
            ) {
                actions.openMetricReloadRequested(openMetricName, newName)
                return
            }
            actions.openMetricReloadRequested(openMetricName)
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.disposables.add(
            () => {
                toolStreamEventsLogic.actions.registerToolListener(LISTENER_ID, {
                    tools: SUBSCRIBED_TOOLS,
                    foregroundOnly: true,
                    onEvent: (event) => actions.toolCompleted(event),
                })
                return () => toolStreamEventsLogic.actions.deregisterToolListener(LISTENER_ID)
            },
            'toolListener',
            { pauseOnPageHidden: false }
        )
    }),
])
