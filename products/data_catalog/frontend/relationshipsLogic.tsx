import {
    dataCatalogRelationshipProposalsCreate,
    dataCatalogRelationshipProposalsAcceptCreate,
    dataCatalogRelationshipProposalsList,
    dataCatalogRelationshipProposalsRejectCreate,
} from './generated/api'
import type { DataCatalogRelationshipProposalApi } from './generated/api.schemas'

type CatalogJoin = Pick<
    ViewLinkApi,
    'id' | 'source_table_name' | 'source_table_key' | 'joining_table_name' | 'joining_table_key' | 'field_name'
>

export type RelationshipStatusFilter = 'all' | 'pending' | 'active' | 'rejected'
export type RelationshipRowStatus = 'pending' | 'active' | 'rejected'

export interface RelationshipsFilters {
    search: string
    status: RelationshipStatusFilter
}

export const DEFAULT_RELATIONSHIPS_FILTERS: RelationshipsFilters = {
    search: '',
    status: 'all',
}

export interface RelationshipRow {
    key: string
    sourceTableName: string
    sourceTableKey: string
    joiningTableName: string
    joiningTableKey: string
    fieldName: string
    rowStatus: RelationshipRowStatus
    confidence: number | null
    reasoning: string
    evidence: unknown
    rejectionReason: string
    reviewedBy: string | null
    viaCatalog: boolean
    proposalId: string | null
    joinId: string | null
}

function projectId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

function apiErrorDetail(error: unknown): string | null {
    return error instanceof ApiError ? error.detail : null
}

const searchRelationshipRows = createFuseSearch<RelationshipRow>([
    'sourceTableName',
    'sourceTableKey',
    'joiningTableName',
    'joiningTableKey',
    'fieldName',
])

