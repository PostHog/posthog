export const relationshipsLogic = kea<relationshipsLogicType>([
    path(['products', 'data_catalog', 'frontend', 'relationshipsLogic']),
    actions({
        openProposal: (table = '') => ({ table }),
        closeProposal: true,
        setProposing: (proposing: boolean) => ({ proposing }),
        setProposalDraft: (draft: Partial<DataCatalogRelationshipProposalApi>) => ({ draft }),
        proposeRelationship: true,
        setFilters: (filters: Partial<RelationshipsFilters>) => ({ filters }),
        acceptProposal: (id: string) => ({ id }),
        rejectProposal: (id: string, rejectionReason: string) => ({ id, rejectionReason }),
        setActionInFlight: (id: string, inFlight: boolean) => ({ id, inFlight }),
        deleteJoin: (join: CatalogJoin) => ({ join }),
    }),
    loaders(() => ({
        // Badge count only — never pull the full proposal payloads (unbounded reasoning/evidence)
        // just to render a number on a tab the user may never open.
        pendingCount: [
            0,
            {
                loadPendingCount: async () => {
                    const response = await dataCatalogRelationshipProposalsList(projectId(), {
                        status: 'proposed',
                        limit: 1,
                    })
                    return response.count ?? 0
                },
            },
        ],
        proposals: [
            [] as DataCatalogRelationshipProposalApi[],
            {
                loadProposals: async () => {
                    const response = await dataCatalogRelationshipProposalsList(projectId())
                    return response.results || []
                },
            },
        ],
        joins: [
            [] as CatalogJoin[],
            {
                loadJoins: async () => {
                    const response = await warehouseViewLinksList(projectId())
                    return response.results || []
                },
            },
        ],
    })),
    reducers({
        proposalOpen: [false, { openProposal: () => true, closeProposal: () => false }],
        proposing: [false, { setProposing: (_, { proposing }) => proposing }],
        proposalDraft: [
            {
                source_table_name: '',
                source_table_key: '',
                joining_table_name: '',
                joining_table_key: '',
                field_name: '',
                reasoning: '',
            } as Pick<
                DataCatalogRelationshipProposalApi,
                | 'source_table_name'
                | 'source_table_key'
                | 'joining_table_name'
                | 'joining_table_key'
                | 'field_name'
                | 'reasoning'
            >,
            {
                openProposal: (_, { table }) => ({
                    source_table_name: table,
                    source_table_key: '',
                    joining_table_name: '',
                    joining_table_key: '',
                    field_name: '',
                    reasoning: '',
                }),
                setProposalDraft: (state, { draft }) => ({ ...state, ...draft }),
            },
        ],
        filters: [
            DEFAULT_RELATIONSHIPS_FILTERS as RelationshipsFilters,
            {
                setFilters: (state, { filters }) => ({ ...state, ...filters }),
            },
        ],
        actionsInFlight: [
            {} as Record<string, boolean>,
            {
                setActionInFlight: (state, { id, inFlight }) => ({ ...state, [id]: inFlight }),
            },
        ],
    }),
    selectors({
        rows: [
            (s) => [s.proposals, s.joins],
            (proposals: DataCatalogRelationshipProposalApi[], joins: CatalogJoin[]): RelationshipRow[] => {
                const acceptedByJoinId = new Map<string, DataCatalogRelationshipProposalApi>()
                proposals
                    .filter((proposal) => proposal.status === 'accepted' && proposal.created_join)
                    .forEach((proposal) => acceptedByJoinId.set(proposal.created_join as string, proposal))

                const joinRows: RelationshipRow[] = joins.map((join) => {
                    const proposal = acceptedByJoinId.get(join.id)
                    return {
                        key: `join-${join.id}`,
                        sourceTableName: join.source_table_name || '',
                        sourceTableKey: join.source_table_key || '',
                        joiningTableName: join.joining_table_name || '',
                        joiningTableKey: join.joining_table_key || '',
                        fieldName: join.field_name || '',
                        rowStatus: 'active',
                        confidence: proposal?.confidence ?? null,
                        reasoning: proposal?.reasoning ?? '',
                        evidence: proposal?.evidence,
                        rejectionReason: '',
                        reviewedBy: proposal?.reviewed_by?.email ?? null,
                        viaCatalog: !!proposal,
                        proposalId: null,
                        joinId: join.id,
                    }
                })

                // An accepted proposal that never persisted a join would otherwise vanish — surface it
                // as an active row. A proposal whose created join is absent from the loaded joins was
                // deleted (soft delete drops it from the list), and the backend treats it as gone, so
                // it must not reappear as an uneditable active row.
                const orphanedAcceptedRows: RelationshipRow[] = proposals
                    .filter((proposal) => proposal.status === 'accepted' && !proposal.created_join)
                    .map((proposal) => ({
                        key: `proposal-${proposal.id}`,
                        sourceTableName: proposal.source_table_name,
                        sourceTableKey: proposal.source_table_key,
                        joiningTableName: proposal.joining_table_name,
                        joiningTableKey: proposal.joining_table_key,
                        fieldName: proposal.field_name,
                        rowStatus: 'active',
                        confidence: proposal.confidence ?? null,
                        reasoning: proposal.reasoning ?? '',
                        evidence: proposal.evidence,
                        rejectionReason: '',
                        reviewedBy: proposal.reviewed_by?.email ?? null,
                        viaCatalog: true,
                        proposalId: proposal.id,
                        joinId: null,
                    }))

                const proposalRows: RelationshipRow[] = proposals
                    .filter((proposal) => proposal.status !== 'accepted')
                    .map((proposal) => ({
                        key: `proposal-${proposal.id}`,
                        sourceTableName: proposal.source_table_name,
                        sourceTableKey: proposal.source_table_key,
                        joiningTableName: proposal.joining_table_name,
                        joiningTableKey: proposal.joining_table_key,
                        fieldName: proposal.field_name,
                        rowStatus: proposal.status === 'rejected' ? 'rejected' : 'pending',
                        confidence: proposal.confidence ?? null,
                        reasoning: proposal.reasoning ?? '',
                        evidence: proposal.evidence,
                        rejectionReason: proposal.rejection_reason || '',
                        reviewedBy: proposal.reviewed_by?.email ?? null,
                        viaCatalog: false,
                        proposalId: proposal.id,
                        joinId: null,
                    }))

                return [...joinRows, ...orphanedAcceptedRows, ...proposalRows]
            },
        ],
        filteredRows: [
            (s) => [s.rows, s.filters],
            (rows: RelationshipRow[], filters: RelationshipsFilters) => {
                const statusMatched =
                    filters.status === 'all' ? rows : rows.filter((row) => row.rowStatus === filters.status)
                return searchRelationshipRows(statusMatched, filters.search)
            },
        ],
        joinsById: [
            (s) => [s.joins],
            (joins: CatalogJoin[]): Record<string, CatalogJoin> =>
                Object.fromEntries(joins.map((join) => [join.id, join])),
        ],
    }),
    listeners(({ values, actions }) => ({
        closeProposal: () => {
            const { propose_table, ...search } = router.values.searchParams
            router.actions.replace(urls.dataCatalog(), search, router.values.hashParams)
        },
        proposeRelationship: async () => {
            if (values.proposing) {
                return
            }
            actions.setProposing(true)
            try {
                await dataCatalogRelationshipProposalsCreate(
                    projectId(),
                    values.proposalDraft as DataCatalogRelationshipProposalApi
                )
                actions.closeProposal()
                actions.loadProposals()
                actions.loadPendingCount()
                lemonToast.success('Relationship proposed for review')
            } catch (error) {
                lemonToast.error(apiErrorDetail(error) || 'Could not propose the relationship')
            } finally {
                actions.setProposing(false)
            }
        },
        acceptProposal: async ({ id }) => {
            if (values.actionsInFlight[id]) {
                return
            }
            actions.setActionInFlight(id, true)
            try {
                await dataCatalogRelationshipProposalsAcceptCreate(projectId(), id)
                lemonToast.success('Relationship accepted and promoted to a warehouse join')
                actions.loadProposals()
                actions.loadJoins()
                actions.loadPendingCount()
            } catch (error) {
                lemonToast.error(apiErrorDetail(error) || 'Could not accept the relationship. Try again.')
            } finally {
                actions.setActionInFlight(id, false)
            }
        },
        rejectProposal: async ({ id, rejectionReason }) => {
            if (values.actionsInFlight[id]) {
                return
            }
            actions.setActionInFlight(id, true)
            try {
                await dataCatalogRelationshipProposalsRejectCreate(projectId(), id, {
                    rejection_reason: rejectionReason || undefined,
                })
                lemonToast.success('Relationship rejected')
                actions.loadProposals()
                actions.loadPendingCount()
            } catch (error) {
                lemonToast.error(apiErrorDetail(error) || 'Could not reject the relationship. Try again.')
            } finally {
                actions.setActionInFlight(id, false)
            }
        },
        deleteJoin: async ({ join }) => {
            await deleteWithUndo({
                endpoint: `environments/${projectId()}/warehouse_view_link`,
                object: { id: join.id, name: `${join.field_name} on ${join.source_table_name}` },
                callback: () => actions.loadJoins(),
            })
        },
        // Refresh after the shared join modal saves. Referencing actionTypes builds
        // viewLinkLogic without mounting it, so the catalog scene doesn't eagerly load
        // the database schema; the modal in RelationshipsTab mounts it when visible.
        [viewLinkLogic.actionTypes.submitViewLinkSuccess]: () => {
            actions.loadJoins()
        },
    })),
    urlToAction(({ actions }) => ({
        // Load the full proposals and joins only when the Relationships tab is actually viewed.
        [urls.dataCatalog()]: (_, searchParams) => {
            if (searchParams.tab === 'relationships') {
                if (typeof searchParams.table === 'string') {
                    actions.setFilters({ search: searchParams.table })
                }
                if (typeof searchParams.propose_table === 'string') {
                    actions.openProposal(searchParams.propose_table)
                }
                actions.loadProposals()
                actions.loadJoins()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadPendingCount()
    }),
])
