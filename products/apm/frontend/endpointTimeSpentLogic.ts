import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { TIME_RANGE_MS, TimeRange, applicationObservabilityLogic } from './applicationObservabilityLogic'
import { apmEndpointTimeSpentList } from './generated/api'
import type { EndpointTimeSpentResponseApi, EndpointsHealthResponseApi } from './generated/api.schemas'

export interface EndpointTimeSpentLogicProps {
    service: string
    endpoint: string
    // null reads every environment, as the scene's environment picker does.
    environment: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface endpointTimeSpentLogicValues {
    timeRange: TimeRange // applicationObservabilityLogic
    currentTeamId: number | null // teamLogic
    timeSpent: EndpointTimeSpentResponseApi | null
    timeSpentFailed: boolean
    timeSpentLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface endpointTimeSpentLogicActions {
    loadEndpointsHealthSuccess: (
        endpointsHealth: EndpointsHealthResponseApi,
        payload?: void | undefined
    ) => {
        endpointsHealth: EndpointsHealthResponseApi
        payload?: void | undefined
    } // applicationObservabilityLogic
    loadTimeSpent: (_: void) => void
    loadTimeSpentFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTimeSpentSuccess: (
        timeSpent: EndpointTimeSpentResponseApi | null,
        payload?: void
    ) => {
        timeSpent: EndpointTimeSpentResponseApi | null
        payload?: void
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface endpointTimeSpentLogicMeta {
    key: string
}

export type endpointTimeSpentLogicType = MakeLogicType<
    endpointTimeSpentLogicValues,
    endpointTimeSpentLogicActions,
    EndpointTimeSpentLogicProps,
    endpointTimeSpentLogicMeta
>

export const endpointTimeSpentLogic = kea<endpointTimeSpentLogicType>([
    props({} as EndpointTimeSpentLogicProps),
    key(({ service, endpoint, environment }) => `${environment}\n${service}\n${endpoint}`),
    path((key) => ['products', 'apm', 'frontend', 'endpointTimeSpentLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], applicationObservabilityLogic, ['timeRange']],
        actions: [applicationObservabilityLogic, ['loadEndpointsHealthSuccess']],
    })),

    loaders(({ props, values }) => ({
        timeSpent: [
            null as EndpointTimeSpentResponseApi | null,
            {
                loadTimeSpent: async (_: void, breakpoint): Promise<EndpointTimeSpentResponseApi | null> => {
                    const dateTo = new Date()
                    const dateFrom = new Date(dateTo.getTime() - TIME_RANGE_MS[values.timeRange])
                    const response = await apmEndpointTimeSpentList(String(values.currentTeamId), {
                        date_from: dateFrom.toISOString(),
                        date_to: dateTo.toISOString(),
                        ...(props.environment !== null ? { environment: props.environment } : {}),
                        service: props.service,
                        endpoint: props.endpoint,
                    })
                    breakpoint()
                    return response
                },
            },
        ],
    })),

    reducers({
        timeSpentFailed: [
            false,
            {
                loadTimeSpent: () => false,
                loadTimeSpentSuccess: () => false,
                loadTimeSpentFailure: () => true,
            },
        ],
    }),

    listeners(({ actions }) => ({
        // The endpoints table reloads on a range change and on every poll, so the breakdown follows it.
        loadEndpointsHealthSuccess: () => actions.loadTimeSpent(),
    })),

    afterMount(({ actions }) => {
        actions.loadTimeSpent()
    }),
])
