import { MakeLogicType, actions, kea, path, reducers } from 'kea'
import { router, urlToAction } from 'kea-router'

import { syncSearchParams, updateSearchParams } from '@posthog/products-error-tracking/frontend/utils'

import { trackedActionToUrl } from 'lib/logic/scenes/trackedActionToUrl'
import { parseTagsFilter } from 'lib/utils/url'
import { Params } from 'scenes/sceneTypes'

import type { DateRange } from '~/queries/schema/schema-general'

/** The three signals APM presents as facets of one product. */
export type ApmSceneTab = 'logs' | 'traces' | 'metrics'

const VALID_APM_TABS: ApmSceneTab[] = ['logs', 'traces', 'metrics']

/** Logs is GA and the likeliest to hold data, so it is the facet a cold `/apm` opens on. */
export const DEFAULT_APM_TAB: ApmSceneTab = 'logs'

export const DEFAULT_APM_DATE_RANGE: DateRange = { date_from: '-1h', date_to: null }

export const DEFAULT_APM_SERVICE_NAMES: string[] = []

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface apmSceneLogicValues {
    activeTab: ApmSceneTab
    dateRange: DateRange
    serviceNames: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface apmSceneLogicActions {
    setActiveTab: (activeTab: ApmSceneTab) => {
        activeTab: ApmSceneTab
    }
    setDateRange: (dateRange: DateRange) => {
        dateRange: DateRange
    }
    setServiceNames: (serviceNames: string[]) => {
        serviceNames: string[]
    }
}

export type apmSceneLogicType = MakeLogicType<apmSceneLogicValues, apmSceneLogicActions>

export const apmSceneLogic = kea<apmSceneLogicType>([
    path(['products', 'apm', 'frontend', 'apmSceneLogic']),
    actions({
        setActiveTab: (activeTab: ApmSceneTab) => ({ activeTab }),
        setDateRange: (dateRange: DateRange) => ({ dateRange }),
        setServiceNames: (serviceNames: string[]) => ({ serviceNames }),
    }),
    reducers({
        activeTab: [DEFAULT_APM_TAB as ApmSceneTab, { setActiveTab: (_, { activeTab }) => activeTab }],
        // Owned by the scene rather than by each facet, so switching facet keeps the window the
        // user chose. This is the difference between one product and three stacked in a tab strip.
        dateRange: [DEFAULT_APM_DATE_RANGE as DateRange, { setDateRange: (_, { dateRange }) => dateRange }],
        // Shared for the same reason as the date range: a link that scopes one facet to a service
        // should still be scoped to it after switching facet.
        serviceNames: [
            DEFAULT_APM_SERVICE_NAMES as string[],
            { setServiceNames: (_, { serviceNames }) => serviceNames },
        ],
    }),
    urlToAction(({ actions, values, cache }) => {
        const syncFromUrl = (_: any, params: Params): void => {
            if (cache.isSyncingUrl) {
                return
            }
            // An unrecognized tab is ignored rather than applied, so a stale or hand-edited link
            // leaves the scene on a facet that renders.
            const requested = params.tab
            if (
                typeof requested === 'string' &&
                VALID_APM_TABS.includes(requested as ApmSceneTab) &&
                requested !== values.activeTab
            ) {
                actions.setActiveTab(requested as ApmSceneTab)
            }

            const serviceNames = parseTagsFilter(params.serviceNames)
            if (serviceNames && serviceNames.join() !== values.serviceNames.join()) {
                actions.setServiceNames(serviceNames)
            }

            if (params.dateRange) {
                try {
                    const dateRange =
                        typeof params.dateRange === 'string' ? JSON.parse(params.dateRange) : params.dateRange
                    if (dateRange.date_from !== values.dateRange.date_from) {
                        actions.setDateRange(dateRange)
                    }
                } catch {
                    // Ignore malformed dateRange JSON in the URL
                }
            }
        }
        return { '*': syncFromUrl }
    }),
    trackedActionToUrl(({ values, cache }) => {
        const syncUrl = (): [string, Params, Record<string, any>, { replace: boolean }] => {
            cache.isSyncingUrl = true
            const result = syncSearchParams(router, (params: Params) => {
                updateSearchParams(params, 'tab', values.activeTab, DEFAULT_APM_TAB)
                updateSearchParams(params, 'serviceNames', values.serviceNames, DEFAULT_APM_SERVICE_NAMES)
                updateSearchParams(
                    params,
                    'dateRange',
                    JSON.stringify(values.dateRange),
                    JSON.stringify(DEFAULT_APM_DATE_RANGE)
                )
                return params
            })
            queueMicrotask(() => {
                cache.isSyncingUrl = false
            })
            return result
        }
        return {
            setActiveTab: () => syncUrl(),
            setDateRange: () => syncUrl(),
            setServiceNames: () => syncUrl(),
        }
    }),
])
