export const dependenciesLogic = kea<dependenciesLogicType>([
    path(['products', 'apm', 'frontend', 'dependenciesLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            applicationObservabilityLogic,
            ['environment', 'timeRange', 'services', 'endpointsService'],
        ],
        actions: [applicationObservabilityLogic, ['requestReload', 'setEndpointsService']],
    })),

    actions({
        setDependencyService: (service: string | null) => ({ service }),
        setShowAllDependencies: (showAll: boolean) => ({ showAll }),
    }),

    reducers({
        dependencyService: [null as string | null, { setDependencyService: (_, { service }) => service }],
        showAllDependencies: [
            false,
            {
                setShowAllDependencies: (_, { showAll }) => showAll,
                setDependencyService: () => false,
            },
        ],
        dependenciesLoadError: [
            false,
            {
                loadDependenciesSuccess: () => false,
                loadDependenciesFailure: () => true,
            },
        ],
        // The API answers 400 with a message saying how to narrow the request when a window is too
        // heavy to read, so that message is shown in place of the generic network error.
        dependenciesLoadErrorDetail: [
            null as string | null,
            {
                loadDependenciesSuccess: () => null,
                loadDependenciesFailure: (_, { errorObject }) =>
                    errorObject?.status === 400 && typeof errorObject.detail === 'string' ? errorObject.detail : null,
            },
        ],
        dependencyLayoutError: [
            false,
            {
                layoutDependencies: () => false,
                layoutDependenciesSuccess: () => false,
                layoutDependenciesFailure: () => true,
            },
        ],
    }),

    loaders(({ values }) => ({
        dependencies: [
            null as DependenciesResponseApi | null,
            {
                loadDependencies: async (_: void, breakpoint): Promise<DependenciesResponseApi> => {
                    await breakpoint(0)
                    const dateTo = new Date()
                    const dateFrom = new Date(dateTo.getTime() - TIME_RANGE_MS[values.timeRange])
                    const response = await apmDependenciesList(String(values.currentTeamId), {
                        date_from: dateFrom.toISOString(),
                        date_to: dateTo.toISOString(),
                        ...(values.environment ? { environment: values.environment } : {}),
                        // Scoped server-side, so a service outside the environment's busiest edges still shows.
                        ...(values.dependencyService ? { service: values.dependencyService } : {}),
                    })
                    breakpoint()
                    return response
                },
            },
        ],
        dependencyLayout: [
            null as DependencyGraph | null,
            {
                layoutDependencies: async (_: void, breakpoint): Promise<DependencyGraph> => {
                    const graph = await layoutServiceGraph(buildDependencyGraph(values.drawnEdges))
                    breakpoint()
                    return graph
                },
            },
        ],
    })),

    selectors({
        edges: [
            (s) => [s.dependencies],
            (dependencies: DependenciesResponseApi | null): DependencyEdgeApi[] => dependencies?.edges ?? [],
        ],
        visibleEdges: [
            (s) => [s.edges, s.dependencyService],
            (edges: DependencyEdgeApi[], service: string | null): DependencyEdgeApi[] =>
                edgesForService(edges, service),
        ],
        drawableEdges: [
            (s) => [s.edges, s.dependencyService],
            (edges: DependencyEdgeApi[], service: string | null): DrawnDependencyEdge[] =>
                drawableEdges(edges, service),
        ],
        drawnEdges: [
            (s) => [s.edges, s.dependencyService, s.showAllDependencies],
            (edges: DependencyEdgeApi[], service: string | null, showAll: boolean): DrawnDependencyEdge[] =>
                edgesToDraw(edges, service, showAll),
        ],
        dependencyLayoutKey: [
            (s) => [s.dependencyLayout],
            (layout: DependencyGraph | null): string => (layout ? graphKey(layout) : ''),
        ],
        split: [
            (s) => [s.edges, s.dependencyService],
            (edges: DependencyEdgeApi[], service: string | null): DependencySplit | null =>
                service ? splitDependencies(edges, service) : null,
        ],
        serviceNames: [
            (s) => [s.edges, s.services, s.dependencyService],
            (edges: DependencyEdgeApi[], services: ServiceHealthApi[], service: string | null): string[] => {
                // A scoped load only returns the picked service's neighbours, so the health list fills in the rest.
                const names = [...new Set([...serviceNamesOf(edges), ...services.map((row) => row.service_name)])]
                return service && !names.includes(service) ? [...names, service] : names
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        requestReload: () => actions.loadDependencies(),
        loadDependenciesSuccess: () => actions.layoutDependencies(),
        setShowAllDependencies: () => actions.layoutDependencies(),
        // The map narrows to the new service right away, so it never shows the last selection when the
        // scoped load fails. The URL's `service` mirrors the pick, so a later URL rewrite (a range or
        // environment change) keeps it.
        setDependencyService: ({ service }) => {
            actions.layoutDependencies()
            actions.loadDependencies()
            if (service !== values.endpointsService) {
                actions.setEndpointsService(service)
            }
        },
    })),

    urlToAction(({ actions, values }) => ({
        [APPLICATION_OBSERVABILITY_PATH]: (_, searchParams) => {
            const service = readScopeParam(searchParams.service)
            // A URL without `service` (Back to the unscoped view) clears the pick too.
            if (searchParams.tab === 'dependencies' && service !== values.dependencyService) {
                actions.setDependencyService(service)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadDependencies()
    }),
])
