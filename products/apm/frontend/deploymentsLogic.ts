export type deploymentsLogicType = MakeLogicType<
    deploymentsLogicValues,
    deploymentsLogicActions,
    Record<string, any>,
    deploymentsLogicMeta
>

export const deploymentsLogic = kea<deploymentsLogicType>([
    path(['products', 'apm', 'frontend', 'deploymentsLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            applicationObservabilityLogic,
            [
                'environment',
                'timeRange',
                'services',
                'servicesHealthLoading',
                'hasLoadError',
                'tab',
                'endpointsService',
            ],
        ],
        actions: [
            applicationObservabilityLogic,
            ['requestReload', 'loadServicesHealthSuccess', 'loadServicesHealthFailure', 'setEndpointsService'],
        ],
    })),

    actions({
        setDeploymentsService: (service: string | null) => ({ service }),
    }),

    reducers({
        pickedService: [null as string | null, { setDeploymentsService: (_, { service }) => service }],
        deploymentsLoadError: [
            false,
            {
                loadDeploymentsSuccess: () => false,
                loadDeploymentsFailure: () => true,
            },
        ],
    }),

    loaders(({ values }) => ({
        deployments: [
            null as DeploymentsResponseApi | null,
            {
                loadDeployments: async (_: void, breakpoint): Promise<DeploymentsResponseApi | null> => {
                    if (!values.deploymentsService) {
                        return null
                    }
                    await breakpoint(0)
                    const dateTo = new Date()
                    const dateFrom = new Date(dateTo.getTime() - TIME_RANGE_MS[values.timeRange])
                    const response = await apmDeploymentsList(String(values.currentTeamId), {
                        date_from: dateFrom.toISOString(),
                        date_to: dateTo.toISOString(),
                        service: values.deploymentsService,
                        ...(values.environment !== null ? { environment: values.environment } : {}),
                    })
                    breakpoint()
                    return response
                },
            },
        ],
    })),

    selectors({
        deploymentsService: [
            (s) => [s.pickedService, s.services],
            (picked: string | null, services: ServiceHealthApi[]): string | null =>
                picked ?? services[0]?.service_name ?? null,
        ],
        serviceNames: [
            (s) => [s.services, s.pickedService],
            (services: ServiceHealthApi[], picked: string | null): string[] => {
                const names = services.map((row) => row.service_name)
                return picked && !names.includes(picked) ? [...names, picked] : names
            },
        ],
        versionsNewestFirst: [
            (s) => [s.deployments],
            (deployments: DeploymentsResponseApi | null): DeploymentVersionApi[] =>
                [...(deployments?.results ?? [])].reverse(),
        ],
    }),

    listeners(({ actions, values }) => ({
        // A reload that refreshes service health loads deployments from loadServicesHealthSuccess.
        requestReload: ({ includeServices }) => {
            if (values.tab === 'deployments' && !includeServices) {
                actions.loadDeployments()
            }
        },
        loadServicesHealthSuccess: () => {
            if (values.tab === 'deployments') {
                actions.loadDeployments()
            }
        },
        // The picked service, or the last loaded list, still names a service to load for the new filter.
        loadServicesHealthFailure: () => {
            if (values.tab === 'deployments') {
                actions.loadDeployments()
            }
        },
        // The URL's `service` is the tab's picked service, so a later URL rewrite (a range or
        // environment change) keeps this pick instead of restoring the one the tab opened with.
        setDeploymentsService: ({ service }) => {
            actions.loadDeployments()
            if (service !== values.endpointsService) {
                actions.setEndpointsService(service)
            }
        },
    })),

    urlToAction(({ actions, values }) => ({
        [APPLICATION_OBSERVABILITY_PATH]: (_, searchParams) => {
            const service = readScopeParam(searchParams.service)
            // A URL without `service` (Back to the unscoped view) clears the pick too.
            if (searchParams.tab === 'deployments' && service !== values.pickedService) {
                actions.setDeploymentsService(service)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadDeployments()
    }),
])
