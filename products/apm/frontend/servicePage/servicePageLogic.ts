const DEFAULT_TIME_RANGE: TimeRange = '-1h'

const TIME_RANGE_MS: Record<TimeRange, number> = {
    '-1h': 60 * 60 * 1000,
    '-6h': 6 * 60 * 60 * 1000,
    '-24h': 24 * 60 * 60 * 1000,
    '-7d': 7 * 24 * 60 * 60 * 1000,
}

function isTimeRange(value: unknown): value is TimeRange {
    return typeof value === 'string' && Object.hasOwn(TIME_RANGE_LABELS, value)
}

function nonEmptyValues(rows: _TracingAttributeBreakdownRowApi[]): string[] {
    return rows.map((row) => row.value).filter((value) => value !== '')
}

/** The health APIs take an absolute window; the span APIs take the relative range. */
function healthWindow(timeRange: TimeRange): { date_from: string; date_to: string } {
    const dateTo = new Date()
    return {
        date_from: new Date(dateTo.getTime() - TIME_RANGE_MS[timeRange]).toISOString(),
        date_to: dateTo.toISOString(),
    }
}

/** Reads the range and scope the URL asks for. Exported for the URL round-trip tests. */
export function servicePageStateFromUrl(searchParams: Record<string, unknown>): {
    timeRange: TimeRange
    scope: ServiceScope
} {
    return {
        timeRange: isTimeRange(searchParams.range) ? searchParams.range : DEFAULT_TIME_RANGE,
        scope: {
            environment: readEnvironmentParam(searchParams.environment),
            version: readScopeParam(searchParams.version),
            operation: readScopeParam(searchParams.operation),
        },
    }
}

