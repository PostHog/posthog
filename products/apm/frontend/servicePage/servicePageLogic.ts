export const servicePageLogic = kea<servicePageLogicType>([
    props({} as ServicePageLogicProps),
    key(({ serviceName }) => serviceName),
    path((key) => ['products', 'apm', 'frontend', 'servicePage', 'servicePageLogic', key]),

    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    actions({
        setTimeRange: (timeRange: TimeRange) => ({ timeRange }),
        setScope: (scope: Partial<ServiceScope>) => ({ scope }),
        loadServiceData: true,
    }),

    reducers({
        timeRange: [DEFAULT_TIME_RANGE as TimeRange, { setTimeRange: (_, { timeRange }) => timeRange }],
        scope: [
            EMPTY_SERVICE_SCOPE as ServiceScope,
            {
                setScope: (state, { scope }) => ({ ...state, ...scope }),
            },
        ],
    }),

    loaders(({ props, values, cache }) => ({
        scopeOptions: [
            { environmentKeys: [], versions: [] } as ServiceScopeOptions,
            {
                fetchScopeOptions: async (_: void, breakpoint) => {
                    await breakpoint(10)
                    const signal = replaceRequest(cache, 'scopeOptions')
                    const projectId = String(values.currentTeamId)
                    const breakdown = (breakdownKey: string): Promise<_TracingAttributeBreakdownRowApi[]> =>
                        tracingSpansAttributeBreakdownCreate(
                            projectId,
                            {
                                query: {
                                    breakdownKey,
                                    breakdownType: 'span_resource_attribute',
                                    dateRange: values.dateRange,
                                    serviceNames: [props.serviceName],
                                },
                            },
                            { signal }
                        ).then((response) => response.results)
                    const [versionRows, ...environmentRows] = await unlessSuperseded(
                        Promise.all([breakdown(VERSION_KEY), ...ENVIRONMENT_KEYS.map(breakdown)]),
                        signal,
                        breakpoint
                    )
                    breakpoint()
                    return {
                        environmentKeys: ENVIRONMENT_KEYS.map((envKey, index) => ({
                            key: envKey,
                            values: nonEmptyValues(environmentRows[index]),
                        })),
                        versions: nonEmptyValues(versionRows),
                    }
                },
            },
        ],
        servicesHealth: [
            null as ServicesHealthResponseApi | null,
            {
                fetchServicesHealth: async (_: void, breakpoint) => {
                    await breakpoint(10)
                    const signal = replaceRequest(cache, 'servicesHealth')
                    const response = await unlessSuperseded(
                        apmServicesList(
                            String(values.currentTeamId),
                            {
                                ...healthWindow(values.timeRange),
                                ...(values.scope.environment !== null ? { environment: values.scope.environment } : {}),
                            },
                            { signal }
                        ),
                        signal,
                        breakpoint
                    )
                    breakpoint()
                    return response
                },
            },
        ],
    })),

    // After the loaders, so their actions exist when these reducers resolve them.
    reducers({
        // A failed fetch leaves the previous response in place, so these keep it from showing as current.
        servicesHealthFailed: [
            false,
            {
                fetchServicesHealth: () => false,
                fetchServicesHealthSuccess: () => false,
                fetchServicesHealthFailure: () => true,
            },
        ],
    }),

    selectors({
        serviceName: [() => [(_, props) => props.serviceName], (serviceName: string): string => serviceName],
        dateRange: [
            (s) => [s.timeRange],
            (timeRange: TimeRange): { date_from: string; date_to: null } => ({ date_from: timeRange, date_to: null }),
        ],
        environmentKey: [
            (s) => [s.scope, s.scopeOptions],
            (scope: ServiceScope, scopeOptions: ServiceScopeOptions): string | null =>
                environmentKeyFor(scope.environment, scopeOptions.environmentKeys),
        ],
        scopeFilters: [
            (s) => [s.scope, s.environmentKey],
            (scope: ServiceScope, environmentKey: string | null): ServiceSpanFilter[] =>
                serviceScopeFilters(scope, environmentKey),
        ],
        service: [
            (s) => [s.servicesHealth, (_, props) => props.serviceName],
            (servicesHealth: ServicesHealthResponseApi | null, serviceName: string): ServiceHealthApi | null =>
                servicesHealth?.results.find((row) => row.service_name === serviceName) ?? null,
        ],
        environments: [
            (s) => [s.servicesHealth],
            (servicesHealth: ServicesHealthResponseApi | null): string[] =>
                (servicesHealth?.environments ?? []).map((environment) => environment ?? ''),
        ],
    }),

    listeners(({ actions, values, selectors }) => ({
        loadServiceData: () => {
            actions.fetchServicesHealth()
        },
        setTimeRange: () => {
            actions.fetchScopeOptions()
            // With an environment picked, the span queries wait for the options to say which key it lives under.
            if (!values.scope.environment) {
                actions.loadServiceData()
            }
        },
        setScope: (_, __, ___, previousState) => {
            // The health API only takes the environment, so a version or operation change leaves it be.
            if (selectors.scope(previousState).environment !== values.scope.environment) {
                actions.loadServiceData()
            }
        },
        fetchScopeOptionsSuccess: () => {
            if (values.scope.environment) {
                actions.loadServiceData()
            }
        },
        fetchScopeOptionsFailure: () => {
            if (values.scope.environment) {
                actions.loadServiceData()
            }
        },
    })),

    actionToUrl(({ values }) => {
        const buildUrl = (): [string, Record<string, any>, Record<string, any>, { replace: boolean }] => {
            const { range, environment, version, operation, ...rest } = router.values.searchParams
            const params: Record<string, any> = { ...rest }
            if (values.timeRange !== DEFAULT_TIME_RANGE) {
                params.range = values.timeRange
            }
            for (const field of ['environment', 'version', 'operation'] as const) {
                const value = values.scope[field]
                if (value || (field === 'environment' && value === '')) {
                    params[field] = scopeParamValue(value)
                }
            }
            return [router.values.location.pathname, params, router.values.hashParams, { replace: true }]
        }
        return {
            setTimeRange: buildUrl,
            setScope: buildUrl,
        }
    }),

    urlToAction(({ actions, values }) => ({
        [SERVICE_PAGE_PATH]: (_, searchParams) => {
            const { timeRange, scope } = servicePageStateFromUrl(searchParams)
            // Scope first: a range change refetches the options, which then load the data with the
            // environment already in place.
            if (
                scope.environment !== values.scope.environment ||
                scope.version !== values.scope.version ||
                scope.operation !== values.scope.operation
            ) {
                actions.setScope(scope)
            }
            if (timeRange !== values.timeRange) {
                actions.setTimeRange(timeRange)
            }
        },
    })),

    afterMount(({ actions, props, values }) => {
        if (!props.serviceName) {
            return
        }
        // The loaders' leading breakpoint folds these into any the URL restore already dispatched.
        actions.fetchScopeOptions()
        if (!values.scope.environment) {
            actions.loadServiceData()
        }
    }),
])
