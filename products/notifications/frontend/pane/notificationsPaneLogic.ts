export const notificationsPaneLogic = kea<notificationsPaneLogicType>([
    path(['products', 'notifications', 'frontend', 'pane', 'notificationsPaneLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], organizationLogic, ['currentOrganization']],
        actions: [
            sidePanelNotificationsLogic,
            ['notificationReceived', 'navigateToNotification'],
            todayShellLogic,
            ['keepSidebarOnNextPage'],
        ],
    })),
    actions({
        paneOpened: (source: NotificationsPaneOpenSource) => ({ source }),
        loadNotifications: true,
        setItems: (items: NotificationEventApi[], nextCursor: string | null) => ({ items, nextCursor }),
        setStatus: (status: NotificationsPaneStatus) => ({ status }),
        loadMore: true,
        appendItems: (items: NotificationEventApi[], nextCursor: string | null) => ({ items, nextCursor }),
        setLoadMoreFailed: (failed: boolean) => ({ failed }),
        prependItem: (item: NotificationEventApi) => ({ item }),
        removeItems: (ids: string[]) => ({ ids }),
        setRead: (ids: string[], read: boolean) => ({ ids, read }),
        setFilters: (filters: NotificationsPaneFilters) => ({ filters }),
        clearFilters: true,
        setShowArchived: (showArchived: boolean) => ({ showArchived }),
        setListIdle: (idle: boolean) => ({ idle }),
        countNewNotification: true,
        showNewNotifications: true,
        openEntry: (entry: NotificationPaneEntry, inOtherProject: boolean) => ({ entry, inOtherProject }),
        toggleRead: (entry: NotificationPaneEntry) => ({ entry }),
        archive: (entry: NotificationPaneEntry) => ({ entry }),
        setLastArchived: (archived: ArchivedForUndo | null) => ({ archived }),
        undoArchive: true,
        moveToInbox: (entry: NotificationPaneEntry) => ({ entry }),
        markAllRead: true,
        loadSummary: true,
        setSummary: (summary: UnreadSummaryApi) => ({ summary }),
    }),
    reducers({
        items: [
            [] as NotificationEventApi[],
            {
                setItems: (_, { items }) => items,
                appendItems: (state, { items }) => {
                    const known = new Set(state.map((item) => item.id))
                    return [...state, ...items.filter((item) => !known.has(item.id))]
                },
                prependItem: (state, { item }) =>
                    state.some((existing) => existing.id === item.id) ? state : [item, ...state],
                removeItems: (state, { ids }) => state.filter((item) => !ids.includes(item.id)),
                setRead: (state, { ids, read }) =>
                    state.map((item) =>
                        ids.includes(item.id) ? { ...item, read, read_at: read ? dayjs().toISOString() : null } : item
                    ),
            },
        ],
        nextCursor: [
            null as string | null,
            {
                setItems: (_, { nextCursor }) => nextCursor,
                appendItems: (_, { nextCursor }) => nextCursor,
            },
        ],
        status: [
            'loading' as NotificationsPaneStatus,
            {
                setStatus: (_, { status }) => status,
                setItems: () => 'ready',
            },
        ],
        loadingMore: [false, { loadMore: () => true, appendItems: () => false, setLoadMoreFailed: () => false }],
        loadMoreFailed: [false, { setLoadMoreFailed: (_, { failed }) => failed, loadMore: () => false }],
        filters: [
            DEFAULT_NOTIFICATIONS_PANE_FILTERS,
            {
                setFilters: (_, { filters }) => filters,
                clearFilters: () => DEFAULT_NOTIFICATIONS_PANE_FILTERS,
            },
        ],
        showArchived: [false, { setShowArchived: (_, { showArchived }) => showArchived }],
        listIdle: [true, { setListIdle: (_, { idle }) => idle }],
        newCount: [
            0,
            {
                countNewNotification: (state) => state + 1,
                setItems: () => 0,
            },
        ],
        activeKey: [
            null as string | null,
            {
                openEntry: (_, { entry }) => entry.key,
                setFilters: () => null,
                clearFilters: () => null,
                setShowArchived: () => null,
            },
        ],
        lastArchived: [null as ArchivedForUndo | null, { setLastArchived: (_, { archived }) => archived }],
        summary: [null as UnreadSummaryApi | null, { setSummary: (_, { summary }) => summary }],
    }),
    selectors({
        projectNames: [
            (s) => [s.currentOrganization],
            (organization: OrganizationType | null): Record<number, string> =>
                Object.fromEntries((organization?.teams ?? []).map((team) => [team.id, team.name])),
        ],
        entries: [
            (s) => [s.items, s.projectNames],
            (items: NotificationEventApi[], projectNames: Record<number, string>): NotificationPaneEntry[] =>
                buildInboxEntries(items, { projectNames }),
        ],
        filtersActive: [
            (s) => [s.filters],
            (filters: NotificationsPaneFilters) => notificationsPaneFiltersActive(filters),
        ],
        hasUnread: [(s) => [s.items], (items: NotificationEventApi[]) => items.some((item) => !item.read)],
        filterQuery: [
            (s) => [s.filters, s.currentTeamId],
            (filters: NotificationsPaneFilters, currentTeamId: number | null) => filtersToQuery(filters, currentTeamId),
        ],
        query: [
            (s) => [s.filterQuery, s.showArchived],
            (filterQuery: NotificationsFilterQuery, showArchived: boolean): NotificationsListParams => ({
                ...filterQuery,
                archived: showArchived,
            }),
        ],
        projectId: [(s) => [s.currentTeamId], (currentTeamId: number | null) => String(currentTeamId ?? '')],
    }),
    listeners(({ actions, values }) => {
        const failed = (verb: string, revert: () => void): void => {
            revert()
            toast.error({ title: `Couldn't ${verb}. Try again` })
        }

        return {
            paneOpened: ({ source }) => {
                posthog.capture('notification panel opened', { surface: 'today_pane', source })
                actions.loadNotifications()
            },
            loadNotifications: async () => {
                actions.setStatus('loading')
                try {
                    const page = await notificationsList(values.projectId, {
                        ...values.query,
                        limit: NOTIFICATIONS_PAGE_SIZE,
                    })
                    actions.setItems(page.results, page.next_cursor ?? null)
                } catch {
                    actions.setStatus('error')
                }
            },
            loadMore: async () => {
                if (!values.nextCursor) {
                    return
                }
                try {
                    const page = await notificationsList(values.projectId, {
                        ...values.query,
                        limit: NOTIFICATIONS_PAGE_SIZE,
                        before: values.nextCursor,
                    })
                    actions.appendItems(page.results, page.next_cursor ?? null)
                } catch {
                    actions.setLoadMoreFailed(true)
                }
            },
            setFilters: ({ filters }) => {
                posthog.capture('notifications pane filtered', { ...filters })
                actions.loadNotifications()
            },
            clearFilters: () => actions.loadNotifications(),
            setShowArchived: () => actions.loadNotifications(),
            showNewNotifications: () => actions.loadNotifications(),
            notificationReceived: ({ notification }) => {
                actions.loadSummary()
                const item = notification as unknown as NotificationEventApi
                if (values.showArchived || !matchesFilters(item, values.filters, values.currentTeamId)) {
                    return
                }
                if (values.listIdle) {
                    actions.prependItem({ ...item, archived: false })
                } else {
                    actions.countNewNotification()
                }
            },
            openEntry: async ({ entry, inOtherProject }) => {
                const { notification } = entry
                posthog.capture('notification opened', {
                    notification_type: notification.notification_type,
                    category: notificationCategory(notification.notification_type),
                    priority: notification.priority,
                    age_seconds: dayjs().diff(dayjs(notification.created_at), 'second'),
                    grouped_count: entry.count,
                })
                if (inOtherProject) {
                    actions.navigateToNotification({ ...notification, metadata: null })
                    return
                }
                actions.keepSidebarOnNextPage()
                if (notification.read) {
                    return
                }
                actions.setRead(ids(entry), true)
                try {
                    if (entry.count > 1) {
                        await notificationsMarkAllReadCreate(values.projectId, groupQuery(entry))
                    } else {
                        await notificationsMarkReadCreate(values.projectId, notification.id)
                    }
                } catch {
                    actions.setRead(ids(entry), false)
                }
                actions.loadSummary()
            },
            toggleRead: async ({ entry }) => {
                const read = !entry.notification.read
                const entryIds = ids(entry)
                actions.setRead(entryIds, read)
                try {
                    if (read && entry.count > 1) {
                        await notificationsMarkAllReadCreate(values.projectId, groupQuery(entry))
                    } else if (read) {
                        await notificationsMarkReadCreate(values.projectId, entry.notification.id)
                    } else if (entry.count > 1) {
                        await notificationsMarkUnreadBulkCreate(values.projectId, { notification_ids: entryIds })
                    } else {
                        await notificationsMarkUnreadCreate(values.projectId, entry.notification.id)
                    }
                } catch {
                    failed(read ? 'mark as read' : 'mark as unread', () => actions.setRead(entryIds, !read))
                }
                actions.loadSummary()
            },
            archive: async ({ entry }) => {
                const previous = values.items
                const entryIds = ids(entry)
                actions.removeItems(entryIds)
                try {
                    const archivedIds = await archiveEntry(values.projectId, entry)
                    const unread = new Set(entry.children.filter((child) => !child.read).map((child) => child.id))
                    actions.setLastArchived({
                        readIds: archivedIds.filter((id) => !unread.has(id)),
                        unreadIds: archivedIds.filter((id) => unread.has(id)),
                    })
                    posthog.capture('notification archived', {
                        notification_type: entry.notification.notification_type,
                        count: archivedIds.length,
                    })
                    toast({
                        title: archivedIds.length > 1 ? `Archived ${archivedIds.length}` : 'Archived',
                        action: { label: 'Undo', onClick: actions.undoArchive },
                    })
                } catch {
                    failed('archive', () => actions.setItems(previous, values.nextCursor))
                }
                actions.loadSummary()
            },
            undoArchive: async () => {
                const archived = values.lastArchived
                if (!archived) {
                    return
                }
                actions.setLastArchived(null)
                try {
                    for (const [notificationIds, markUnread] of [
                        [archived.readIds, false],
                        [archived.unreadIds, true],
                    ] as const) {
                        for (const chunk of chunks(notificationIds, BULK_IDS_MAX)) {
                            await notificationsUnarchiveBulkCreate(values.projectId, {
                                notification_ids: chunk,
                                mark_unread: markUnread,
                            })
                        }
                    }
                    posthog.capture('notification unarchived', {
                        count: archived.readIds.length + archived.unreadIds.length,
                        source: 'undo',
                    })
                } catch {
                    toast.error({ title: "Couldn't undo. Try again" })
                }
                actions.loadNotifications()
                actions.loadSummary()
            },
            moveToInbox: async ({ entry }) => {
                const previous = values.items
                actions.removeItems(ids(entry))
                try {
                    await notificationsUnarchiveCreate(values.projectId, entry.notification.id, {})
                    posthog.capture('notification unarchived', { count: 1, source: 'move_to_inbox' })
                    toast({ title: 'Moved to inbox' })
                } catch {
                    failed('move to inbox', () => actions.setItems(previous, values.nextCursor))
                }
                actions.loadSummary()
            },
            markAllRead: async () => {
                const unreadIds = values.items.filter((item) => !item.read).map((item) => item.id)
                actions.setRead(unreadIds, true)
                try {
                    await notificationsMarkAllReadCreate(values.projectId, values.filterQuery)
                } catch {
                    failed('mark all as read', () => actions.setRead(unreadIds, false))
                }
                actions.loadSummary()
            },
            loadSummary: async () => {
                const summary = await notificationsUnreadCountRetrieve(values.projectId).catch(() => null)
                if (summary) {
                    actions.setSummary(summary)
                }
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadSummary()
    }),
])
