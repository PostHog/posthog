export const NOTIFICATIONS_PAGE_SIZE = 30
const BULK_IDS_MAX = 500

export type NotificationsPaneStatus = 'loading' | 'error' | 'ready'
export type NotificationsPaneOpenSource = 'rail' | 'tab_bar' | 'toast'

interface ArchivedForUndo {
    readIds: string[]
    unreadIds: string[]
}

function chunks<T>(items: T[], size: number): T[][] {
    return Array.from({ length: Math.ceil(items.length / size) }, (_, index) =>
        items.slice(index * size, (index + 1) * size)
    )
}

function ids(entry: NotificationPaneEntry): string[] {
    return entry.children.map((child) => child.id)
}

function groupQuery(entry: NotificationPaneEntry): Parameters<typeof notificationsArchiveAllCreate>[1] {
    const { notification } = entry
    return {
        notification_type: notification.notification_type,
        resource_type: notification.resource_type ?? undefined,
        resource_id: notification.resource_id,
        team_id: notification.team_id ?? undefined,
    }
}

async function archiveEntry(projectId: string, entry: NotificationPaneEntry): Promise<string[]> {
    if (entry.count > 1) {
        return (await notificationsArchiveAllCreate(projectId, groupQuery(entry))).notification_ids
    }
    await notificationsArchiveCreate(projectId, entry.notification.id)
    return ids(entry)
}

