import { MakeLogicType, actions, afterMount, connect, kea, path } from 'kea'

import { liveEventsHostOrigin } from 'lib/utils/apiHost'
import { retryWithBackoff } from 'lib/utils/async'
import { teamLogic } from 'scenes/teamLogic'

import { connectToNotificationsSSE } from '~/layout/navigation-3000/sidepanel/panels/activity/notificationsSSE'
import { InAppNotification, ResourceEditedEvent } from '~/types'

import type { TeamPublicType, TeamType } from '../../../../frontend/src/types'
import { NotificationEventApi } from '../generated/api.schemas'
import { RESOURCE_EDITED_EVENT_TYPE, resourceEditedLogic } from '../resourceEditedLogic'

const RETRY_ATTEMPTS = 3
const RETRY_INITIAL_DELAY_MS = 30000
const RETRY_BACKOFF_MULTIPLIER = 4

function toNotificationEvent(notification: InAppNotification): NotificationEventApi {
    return {
        ...notification,
        archived: false,
        source_type: notification.source_type as NotificationEventApi['source_type'],
        metadata: notification.metadata as NotificationEventApi['metadata'],
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface notificationsLiveLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface notificationsLiveLogicActions {
    resourceEdited: (event: ResourceEditedEvent) => {
        event: ResourceEditedEvent
    } // resourceEditedLogic
    notificationReceived: (notification: NotificationEventApi) => {
        notification: NotificationEventApi
    }
    reconnected: () => {
        value: true
    }
}

export type notificationsLiveLogicType = MakeLogicType<notificationsLiveLogicValues, notificationsLiveLogicActions>

/** The notifications live stream for the new navigation, open while something shows notifications. */
export const notificationsLiveLogic = kea<notificationsLiveLogicType>([
    path(['products', 'notifications', 'frontend', 'pane', 'notificationsLiveLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
        actions: [resourceEditedLogic, ['resourceEdited']],
    })),
    actions({
        notificationReceived: (notification: NotificationEventApi) => ({ notification }),
        reconnected: true,
    }),
    afterMount(({ actions, values, cache }) => {
        cache.disposables.add(
            () => {
                const token = values.currentTeam?.live_events_token
                const host = liveEventsHostOrigin()
                if (!token || !host) {
                    return () => {}
                }
                const abortController = new AbortController()
                let attempts = 0
                const onMessage = (notification: InAppNotification): void => {
                    if (notification.notification_type === RESOURCE_EDITED_EVENT_TYPE) {
                        actions.resourceEdited(notification as unknown as ResourceEditedEvent)
                        return
                    }
                    actions.notificationReceived(toNotificationEvent(notification))
                }
                void retryWithBackoff(
                    () => {
                        attempts += 1
                        if (attempts > 1) {
                            actions.reconnected()
                        }
                        return connectToNotificationsSSE(
                            `${host}/notifications`,
                            token,
                            abortController.signal,
                            onMessage
                        )
                    },
                    {
                        maxAttempts: RETRY_ATTEMPTS,
                        initialDelayMs: RETRY_INITIAL_DELAY_MS,
                        backoffMultiplier: RETRY_BACKOFF_MULTIPLIER,
                        signal: abortController.signal,
                    }
                ).catch(() => {})
                return () => abortController.abort()
            },
            'notificationsStream',
            { pauseOnPageHidden: true }
        )
    }),
])
