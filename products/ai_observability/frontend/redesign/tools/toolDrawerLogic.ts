export const toolDrawerLogic = kea<toolDrawerLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'tools', 'toolDrawerLogic']),
    connect(() => ({
        values: [
            listFiltersLogic(TOOLS_LIST_FILTERS),
            ['filters'],
            shellScopeLogic,
            ['dateFrom', 'dateTo', 'filterTestAccounts'],
        ],
    })),
    actions({
        openTool: (item: ToolListItemApi) => ({ item }),
        setSeed: (seed: EntitySeed<ToolListItemApi>) => ({ seed }),
        setTraceSection: (section: ToolTraceSection) => ({ section }),
        close: true,
        retry: true,
        previewsRequested: (traceIds: string[]) => ({ traceIds }),
        previewsFailed: (traceIds: string[]) => ({ traceIds }),
        previewsLoaded: (items: TracePreviewApi[]) => ({ items }),
    }),
    loaders(() => ({
        detail: [
            null as ReadFor<ToolGroupDetailApi> | null,
            {
                loadToolDetail: async (request: EntityRequest, breakpoint): Promise<ReadFor<ToolGroupDetailApi>> => {
                    const value = await latest(
                        aiObservabilityToolsRetrieve(
                            String(ApiConfig.getCurrentProjectId()),
                            request.key,
                            request.params
                        ),
                        breakpoint
                    )
                    return { request, value }
                },
            },
        ],
        recentFailures: [
            null as ReadFor<TraceListItemApi[]> | null,
            {
                loadToolRecentFailures: async (request: ToolTracesRequest, breakpoint) =>
                    readRecentTraces(request, { failed_tool: request.name }, breakpoint),
            },
        ],
        recentCalls: [
            null as ReadFor<TraceListItemApi[]> | null,
            {
                loadToolRecentCalls: async (request: ToolTracesRequest, breakpoint) =>
                    readRecentTraces(request, { tool: request.name }, breakpoint),
            },
        ],
    })),
    reducers({
        seed: [
            null as EntitySeed<ToolListItemApi> | null,
            {
                setSeed: (_, { seed }) => seed,
                close: () => null,
            },
        ],
        detailFailure: [
            null as LoadFailure | null,
            {
                loadToolDetail: () => null,
                loadToolDetailFailure: (_, { errorObject }) => toLoadFailure(errorObject),
            },
        ],
        recentFailuresFailed: [
            false,
            {
                loadToolRecentFailures: () => false,
                loadToolRecentFailuresFailure: () => true,
            },
        ],
        recentCallsFailed: [
            false,
            {
                loadToolRecentCalls: () => false,
                loadToolRecentCallsFailure: () => true,
            },
        ],
        previews: [
            noEntries<TraceCellLoad<TracePreviewApi>>() as CellLoads<TracePreviewApi>,
            {
                previewsRequested: (state, { traceIds }) => withRequested(state, traceIds),
                previewsFailed: (state, { traceIds }) => withFailed(state, traceIds),
                previewsLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.traceId, item])
                    ),
            },
        ],
    }),
    selectors({
        openKey: [
            () => [router.selectors.location],
            ({ pathname, search }: { pathname: string; search: string }): string | null =>
                removeProjectIdIfPresent(pathname) === TOOLS_LIST_FILTERS.path
                    ? entityKeyParam(rawSearchParam(search, TOOL_PARAM))
                    : null,
        ],
        // In the URL with the trace, so a refresh or a step through history steps through the same section.
        traceSection: [
            () => [router.selectors.location],
            ({ search }: { search: string }): ToolTraceSection =>
                rawSearchParam(search, TRACE_SECTION_PARAM) === 'failures' ? 'failures' : 'calls',
        ],
        readParams: [
            (s) => [s.filters, s.dateFrom, s.dateTo, s.filterTestAccounts],
            (
                filters: ListFilters,
                dateFrom: string,
                dateTo: string | null,
                filterTestAccounts: boolean
            ): DiagnosticsDrawerParams => drawerReadParams(filters, { dateFrom, dateTo, filterTestAccounts }),
        ],
        request: [
            (s) => [s.openKey, s.readParams],
            (openKey: string | null, readParams: DiagnosticsDrawerParams): EntityRequest | null =>
                openKey ? { key: openKey, params: readParams } : null,
        ],
        openName: [
            (s) => [s.openKey, s.seed, s.detail],
            (
                openKey: string | null,
                seed: EntitySeed<ToolListItemApi> | null,
                detail: ReadFor<ToolGroupDetailApi> | null
            ): string | null => rowWithKey(openKey, [detail?.value.item, seed?.item])?.name ?? null,
        ],
        tracesRequest: [
            (s) => [s.openName, s.readParams],
            (openName: string | null, readParams: DiagnosticsDrawerParams): ToolTracesRequest | null =>
                openName ? { name: openName, params: readParams } : null,
        ],
        item: [
            (s) => [s.detail, s.seed, s.request, s.detailFailure],
            (
                detail: ReadFor<ToolGroupDetailApi> | null,
                seed: EntitySeed<ToolListItemApi> | null,
                request: EntityRequest | null,
                detailFailure: LoadFailure | null
            ): ToolListItemApi | null =>
                shownItem(valueFor(detail, request)?.item ?? null, seed, request, detailFailure),
        ],
        detailLoad: [
            (s) => [s.detail, s.request, s.detailFailure],
            (
                detail: ReadFor<ToolGroupDetailApi> | null,
                request: EntityRequest | null,
                detailFailure: LoadFailure | null
            ): DetailLoad<ToolGroupDetailApi> => detailLoadOf(valueFor(detail, request), detailFailure),
        ],
        // A tool with no captured result, or none that failed, has no failures to list.
        showsFailures: [(s) => [s.item], (item: ToolListItemApi | null): boolean => !!item?.failures],
        // Read only once the row or the detail shows failures, so a tool without them costs no scan of the range.
        failuresRequest: [
            (s) => [s.tracesRequest, s.showsFailures],
            (tracesRequest: ToolTracesRequest | null, showsFailures: boolean): ToolTracesRequest | null =>
                showsFailures ? tracesRequest : null,
        ],
        recentFailuresLoad: [
            (s) => [s.recentFailures, s.failuresRequest, s.recentFailuresFailed],
            (
                recentFailures: ReadFor<TraceListItemApi[]> | null,
                failuresRequest: ToolTracesRequest | null,
                recentFailuresFailed: boolean
            ): TraceCellLoad<TraceListItemApi[]> =>
                readLoadOf(valueFor(recentFailures, failuresRequest), recentFailuresFailed),
        ],
        recentCallsLoad: [
            (s) => [s.recentCalls, s.tracesRequest, s.recentCallsFailed, s.detailFailure],
            (
                recentCalls: ReadFor<TraceListItemApi[]> | null,
                tracesRequest: ToolTracesRequest | null,
                recentCallsFailed: boolean,
                detailFailure: LoadFailure | null
            ): TraceCellLoad<TraceListItemApi[]> =>
                recentTracesLoadOf(
                    valueFor(recentCalls, tracesRequest),
                    recentCallsFailed,
                    !!tracesRequest,
                    detailFailure
                ),
        ],
        traceRows: [
            (s) => [s.traceSection, s.recentFailuresLoad, s.recentCallsLoad],
            (
                traceSection: ToolTraceSection,
                recentFailuresLoad: TraceCellLoad<TraceListItemApi[]>,
                recentCallsLoad: TraceCellLoad<TraceListItemApi[]>
            ): TraceListRow[] => {
                const load = traceSection === 'failures' ? recentFailuresLoad : recentCallsLoad
                return load.status === 'ready' ? load.value.map(traceRowOf) : []
            },
        ],
        viewAllHref: [
            (s) => [s.openName, router.selectors.location, router.selectors.searchParams],
            (
                openName: string | null,
                location: { pathname: string; search: string },
                searchParams: Record<string, unknown>
            ): string | null =>
                openName ? scopedTracesHref(location, searchParams, { kind: 'tool', value: openName }) : null,
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const readPreviews = createPreviewReader(cache, actions)
        const trackRecentTracesFailure = (errorObject: unknown): void => {
            if (isReportedFailure(errorObject)) {
                diagnosticsTracking.readFailed({ kind: 'tool', read: 'recent_traces' })
            }
        }
        return {
            openTool: ({ item }) => {
                if (item.key === values.openKey) {
                    return
                }
                actions.setSeed({ item, params: values.readParams })
                diagnosticsTracking.entityOpened({ kind: 'tool', trigger: 'row' })
                router.actions.push(
                    ...currentUrlWith(router.values, {
                        ...CLOSED_TRACE_DRAWER,
                        [TOOL_PARAM]: item.key,
                        [TRACE_SECTION_PARAM]: undefined,
                    })
                )
            },
            close: () => {
                router.actions.push(
                    ...currentUrlWith(router.values, { [TOOL_PARAM]: undefined, [TRACE_SECTION_PARAM]: undefined })
                )
            },
            // Set on the entry the trace opens from, so the entry the trace pushes carries it too.
            setTraceSection: ({ section }) => {
                router.actions.replace(...currentUrlWith(router.values, { [TRACE_SECTION_PARAM]: section }))
            },
            retry: () => {
                const {
                    request,
                    tracesRequest,
                    failuresRequest,
                    detailFailure,
                    recentFailuresFailed,
                    recentCallsFailed,
                } = values
                if (request && detailFailure === 'failed') {
                    actions.loadToolDetail(request)
                }
                if (failuresRequest && recentFailuresFailed) {
                    actions.loadToolRecentFailures(failuresRequest)
                }
                if (tracesRequest && recentCallsFailed) {
                    actions.loadToolRecentCalls(tracesRequest)
                }
            },
            loadToolDetailFailure: ({ errorObject }) => {
                if (isReportedFailure(errorObject)) {
                    diagnosticsTracking.readFailed({ kind: 'tool', read: 'detail' })
                }
            },
            loadToolRecentFailuresFailure: ({ errorObject }) => trackRecentTracesFailure(errorObject),
            loadToolRecentCallsFailure: ({ errorObject }) => trackRecentTracesFailure(errorObject),
            loadToolRecentFailuresSuccess: ({ recentFailures }) => readPreviews(recentFailures.value, values.previews),
            loadToolRecentCallsSuccess: ({ recentCalls }) => readPreviews(recentCalls.value, values.previews),
        }
    }),
    // Fire on mount with the URL's tool, then each time the open tool or its selection changes, the traces once the
    // tool's name is known. A trace opened over the drawer changes neither, so the drawer keeps what it read.
    subscriptions(({ actions, values }) => ({
        request: (request: EntityRequest | null, previous: EntityRequest | null | undefined) => {
            if (!request || (previous && objectsEqual(request, previous))) {
                return
            }
            if (request.key !== previous?.key && values.seed?.item.key !== request.key) {
                diagnosticsTracking.entityOpened({ kind: 'tool', trigger: 'url' })
            }
            actions.loadToolDetail(request)
        },
        tracesRequest: (request: ToolTracesRequest | null, previous: ToolTracesRequest | null | undefined) => {
            if (request && !(previous && objectsEqual(request, previous))) {
                actions.loadToolRecentCalls(request)
            }
        },
        failuresRequest: (request: ToolTracesRequest | null, previous: ToolTracesRequest | null | undefined) => {
            if (request && !(previous && objectsEqual(request, previous))) {
                actions.loadToolRecentFailures(request)
            }
        },
    })),
])
