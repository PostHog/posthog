// pinned: the param of the open tool's key, which saved links read
const TOOL_PARAM = 'tool'
// pinned: the param of the section an open trace steps through, which saved links read
const TRACE_SECTION_PARAM = 'trace_section'

/** The drawer section a trace opened from, whose traces the trace drawer steps through. */
export type ToolTraceSection = 'failures' | 'calls'

/** The traces list's tool scopes take the name, which a row or the detail gives the drawer. */
export interface ToolTracesRequest {
    name: string
    params: DiagnosticsDrawerParams
}

async function readRecentTraces(
    request: ToolTracesRequest,
    scope: Pick<AiObservabilityTracesListParams, 'tool' | 'failed_tool'>,
    breakpoint: () => void
): Promise<ReadFor<TraceListItemApi[]>> {
    const page = await latest(
        aiObservabilityTracesList(String(ApiConfig.getCurrentProjectId()), {
            ...request.params,
            ...scope,
            limit: RECENT_TRACES_LIMIT,
        }),
        breakpoint
    )
    return { request, value: page.items }
}

