export const TOOLS_LIST_FILTERS: ListFiltersLogicProps = {
    listId: 'tools',
    path: urls.aiObservabilityTools(),
    // pinned: the search param of the tools list, which saved links read
    searchParam: TOOLS_SEARCH_PARAM,
}

export type ToolsSelectionParams = Omit<AiObservabilityToolsListParams, 'limit' | 'offset'>

export type ToolsPageRequest = DiagnosticsPageRequest<AiObservabilityToolsListParams>

export type ShownToolsPage = ShownDiagnosticsPage<ToolListApi, AiObservabilityToolsListParams>

function urlOrder(search: string): AiObservabilityToolsListOrder | null {
    return enumValue(AiObservabilityToolsListOrder, rawSearchParam(search, LIST_ORDER_PARAM))
}

