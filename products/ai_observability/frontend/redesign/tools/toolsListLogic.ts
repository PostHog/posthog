export const toolsListLogic = kea<toolsListLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'tools', 'toolsListLogic']),
    connect(() => ({
        values: [
            listFiltersLogic(TOOLS_LIST_FILTERS),
            ['filters'],
            shellScopeLogic,
            ['dateFrom', 'dateTo', 'filterTestAccounts'],
        ],
    })),
    actions({
        selectionChanged: true,
        reload: true,
        setOrder: (order: AiObservabilityToolsListOrder | null) => ({ order }),
        setPageIndex: (pageIndex: number) => ({ pageIndex }),
    }),
    loaders(({ cache }) => ({
        page: [
            null as ToolListApi | null,
            {
                loadToolsPage: async (request: ToolsPageRequest, breakpoint): Promise<ToolListApi> =>
                    readAbortablePage(
                        cache,
                        (signal) =>
                            aiObservabilityToolsList(String(ApiConfig.getCurrentProjectId()), request.params, {
                                signal,
                            }),
                        breakpoint
                    ),
            },
        ],
    })),
    reducers({
        order: [null as AiObservabilityToolsListOrder | null, { setOrder: (_, { order }) => order }],
        // Kept while the next page loads, so the sorted column does not blink off on each selection change.
        appliedOrder: [
            null as AiObservabilityToolsListOrder | null,
            { loadToolsPageSuccess: (current, { page }) => page?.order ?? current },
        ],
        // Kept while another page loads, so a page that fails to load leaves the pager where the rows are.
        shown: [
            null as ShownToolsPage | null,
            {
                selectionChanged: () => null,
                loadToolsPageSuccess: (current, { page, payload }) => (payload ? { page, request: payload } : current),
            },
        ],
        pageError: [
            null as unknown,
            {
                loadToolsPage: () => null,
                loadToolsPageFailure: (_, { errorObject }) => errorObject ?? true,
            },
        ],
    }),
    selectors({
        selectionParams: [
            (s) => [s.filters, s.dateFrom, s.dateTo, s.filterTestAccounts, s.order],
            (
                filters: ListFilters,
                dateFrom: string,
                dateTo: string | null,
                filterTestAccounts: boolean,
                order: AiObservabilityToolsListOrder | null
            ): ToolsSelectionParams =>
                diagnosticsListParams(
                    filters,
                    { dateFrom, dateTo, filterTestAccounts },
                    AiObservabilityToolsListView,
                    order
                ),
        ],
        sortedBy: [
            (s) => [s.order, s.appliedOrder],
            (
                order: AiObservabilityToolsListOrder | null,
                appliedOrder: AiObservabilityToolsListOrder | null
            ): AiObservabilityToolsListOrder | null => order ?? appliedOrder,
        ],
        pageIndex: [(s) => [s.shown], (shown: ShownToolsPage | null): number => shown?.request.pageIndex ?? 0],
        items: [(s) => [s.shown], (shown: ShownToolsPage | null): ToolListItemApi[] => shown?.page.results ?? []],
        counts: [
            (s) => [s.shown],
            (shown: ShownToolsPage | null): ToolListCountsApi | null => shown?.page.counts ?? null,
        ],
        count: [(s) => [s.shown], (shown: ShownToolsPage | null): number => shown?.page.count ?? 0],
        nothingCaptured: [(s) => [s.shown], (shown: ShownToolsPage | null): boolean => !!shown?.page.nothingCaptured],
        refreshing: [
            (s) => [s.pageLoading, s.shown],
            (pageLoading: boolean, shown: ShownToolsPage | null): boolean => pageLoading && shown !== null,
        ],
        canShowPrevious: [
            (s) => [s.pageIndex, s.pageLoading],
            (pageIndex: number, pageLoading: boolean): boolean => pageIndex > 0 && !pageLoading,
        ],
        canShowNext: [
            (s) => [s.pageIndex, s.count, s.pageLoading],
            (pageIndex: number, count: number, pageLoading: boolean): boolean =>
                pageIndex + 1 < pageCount(count, DIAGNOSTICS_PAGE_SIZE) && !pageLoading,
        ],
        rangeTooLongDetail: [
            (s) => [s.pageError],
            (pageError: unknown): string | null => rangeTooLongDetail(pageError),
        ],
        state: [
            (s) => [s.shown, s.pageError],
            (shown: ShownToolsPage | null, pageError: unknown): ListTableState =>
                diagnosticsListState(shown, pageError),
        ],
    }),
    listeners(({ actions, values }) => {
        const loadPage = (pageIndex: number): void => {
            actions.loadToolsPage({
                pageIndex,
                params: { ...values.selectionParams, ...pageParams(pageIndex, DIAGNOSTICS_PAGE_SIZE) },
            })
        }
        return {
            selectionChanged: () => loadPage(0),
            setPageIndex: ({ pageIndex }) => loadPage(pageIndex),
            reload: () => loadPage(values.pageIndex),
            setOrder: ({ order }) => {
                const { location } = router.values
                if (
                    order !== null &&
                    removeProjectIdIfPresent(location.pathname) === TOOLS_LIST_FILTERS.path &&
                    urlOrder(location.search) !== order
                ) {
                    router.actions.replace(...currentUrlWith(router.values, { [LIST_ORDER_PARAM]: order }))
                }
            },
            loadToolsPageFailure: ({ errorObject }) => {
                if (rangeTooLongDetail(errorObject) === null) {
                    diagnosticsTracking.readFailed({ kind: 'tool', read: 'list' })
                }
                // With no rows on screen the list shows the error itself.
                if (values.shown) {
                    lemonToast.error("Couldn't load tools. Try again.")
                }
            },
        }
    }),
    // Before the subscription, so the order in the URL is set when the list first reads.
    urlToAction(({ actions, values }) => ({
        [TOOLS_LIST_FILTERS.path]: (_, __, ___, { search }) => {
            const order = urlOrder(search)
            if (order !== values.order) {
                actions.setOrder(order)
            }
        },
    })),
    // Fires on mount with the settled filters, range and order, then on each change that must read page one again.
    subscriptions(({ actions }) => ({
        selectionParams: (next: ToolsSelectionParams, previous: ToolsSelectionParams | undefined) => {
            if (!previous || !objectsEqual(next, previous)) {
                actions.selectionChanged()
            }
        },
    })),
])
