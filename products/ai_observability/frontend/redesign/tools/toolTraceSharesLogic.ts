import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { ApiConfig } from 'lib/api'

import { aiObservabilityToolsTraceSharesCreate } from '../../generated/api'
import type {
    AiObservabilityToolsListParams,
    AiObservabilityToolsTraceSharesCreateParams,
    ToolListApi,
} from '../../generated/api.schemas'
import { diagnosticsTracking } from '../diagnostics/diagnosticsTracking'
import { withFailed, withLoaded, withRequested } from '../shared/cellLoads'
import type { TraceCellLoad } from '../shared/cellLoads'
import { CellEntry, createPageCellReader } from '../shared/pageCellReader'
import { noEntries } from '../shared/readOrFailure'
import { ToolsPageRequest, ToolsSelectionParams, toolsListLogic } from './toolsListLogic'

// A tool's share of the range's traces does not depend on the view, the order, the search or the page, so those never
// ask again.
function traceSharesParams({
    view,
    order,
    search,
    limit,
    offset,
    ...params
}: AiObservabilityToolsListParams): AiObservabilityToolsTraceSharesCreateParams {
    return params
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface toolTraceSharesLogicValues {
    selectionParams: ToolsSelectionParams // toolsListLogic
    traceShares: ReadonlyMap<string, TraceCellLoad<number>>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface toolTraceSharesLogicActions {
    loadToolsPageFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    } // toolsListLogic
    loadToolsPageSuccess: (
        page: ToolListApi,
        payload?: ToolsPageRequest | undefined
    ) => {
        page: ToolListApi
        payload?: ToolsPageRequest
    } // toolsListLogic
    reload: () => {
        value: true
    } // toolsListLogic
    selectionChanged: () => {
        value: true
    } // toolsListLogic
    traceSharesFailed: (keys: string[]) => {
        keys: string[]
    }
    traceSharesLoaded: (entries: CellEntry<number>[]) => {
        entries: CellEntry<number>[]
    }
    traceSharesParamsChanged: () => {
        value: true
    }
    traceSharesRequested: (keys: string[]) => {
        keys: string[]
    }
}

export type toolTraceSharesLogicType = MakeLogicType<toolTraceSharesLogicValues, toolTraceSharesLogicActions>

export const toolTraceSharesLogic = kea<toolTraceSharesLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'tools', 'toolTraceSharesLogic']),
    connect(() => ({
        values: [toolsListLogic, ['selectionParams']],
        actions: [toolsListLogic, ['loadToolsPageSuccess', 'loadToolsPageFailure', 'selectionChanged', 'reload']],
    })),
    actions({
        traceSharesParamsChanged: true,
        traceSharesRequested: (keys: string[]) => ({ keys }),
        traceSharesFailed: (keys: string[]) => ({ keys }),
        traceSharesLoaded: (entries: CellEntry<number>[]) => ({ entries }),
    }),
    reducers({
        traceShares: [
            noEntries<TraceCellLoad<number>>(),
            {
                traceSharesParamsChanged: () => noEntries<TraceCellLoad<number>>(),
                traceSharesRequested: (state, { keys }) => withRequested(state, keys),
                traceSharesFailed: (state, { keys }) => withFailed(state, keys),
                traceSharesLoaded: (state, { entries }) => withLoaded(state, entries),
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const reader = createPageCellReader<AiObservabilityToolsTraceSharesCreateParams, number>({
            cache,
            loads: () => values.traceShares,
            paramsChanged: actions.traceSharesParamsChanged,
            requested: actions.traceSharesRequested,
            failed: (keys) => {
                actions.traceSharesFailed(keys)
                diagnosticsTracking.readFailed({ kind: 'tool', read: 'trace_shares' })
            },
            loaded: actions.traceSharesLoaded,
            request: async (keys, params) => {
                const { items } = await aiObservabilityToolsTraceSharesCreate(
                    String(ApiConfig.getCurrentProjectId()),
                    { keys },
                    params
                )
                return items.map(({ key, traceShare }) => [key, traceShare])
            },
        })
        return {
            selectionChanged: () => reader.scopeTo(traceSharesParams(values.selectionParams)),
            // A reload shows the page again once it lands, and its shares are read again with it.
            reload: reader.pageReloading,
            loadToolsPageFailure: reader.pageFailed,
            loadToolsPageSuccess: async ({ page, payload }) => {
                if (payload) {
                    await reader.pageLoaded(
                        page.results.map((item) => item.key),
                        traceSharesParams(payload.params)
                    )
                }
            },
        }
    }),
])
