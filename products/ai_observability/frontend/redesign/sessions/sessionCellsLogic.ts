import { ApiConfig } from 'lib/api'

import { aiObservabilityTracesPeopleCreate, aiObservabilityTracesPreviewsCreate } from '../../generated/api'
import type {
    SessionListItemApi,
    TracePageWithBoundsRequestApi,
    TracePersonApi,
    TracePersonItemApi,
    TracePreviewApi,
} from '../../generated/api.schemas'
import { TraceCellLoad, withFailed, withLoaded, withRequested } from '../shared/cellLoads'
import { createCellReader } from '../shared/cellReader'
import { noEntries } from '../shared/readOrFailure'
import { sessionsListLogic } from './sessionsListLogic'

export type SessionCellRead = 'titles' | 'people'

function peopleRequest(rows: SessionListItemApi[]): TracePageWithBoundsRequestApi {
    const createdAts = rows.map((row) => row.firstTraceCreatedAt).sort((a, b) => Date.parse(a) - Date.parse(b))
    return {
        trace_ids: rows.map((row) => row.firstTraceId),
        earliest_created_at: createdAts[0],
        latest_created_at: createdAts[createdAts.length - 1],
    }
}

