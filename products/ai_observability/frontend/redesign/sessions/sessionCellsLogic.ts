import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { ApiConfig } from 'lib/api'

import { aiObservabilitySessionsPeopleCreate, aiObservabilitySessionsPreviewsCreate } from '../../generated/api'
import type {
    SessionListItemApi,
    SessionPersonItemApi,
    SessionPreviewApi,
    TracePersonApi,
} from '../../generated/api.schemas'
import type { AiObservabilitySessionsListParams, SessionListApi } from '../../generated/api.schemas'
import { TraceCellLoad, rowsToRead, withFailed, withLoaded, withRequested } from '../shared/cellLoads'
import { createCellReader } from '../shared/cellReader'
import { noEntries } from '../shared/readOrFailure'
import { sessionsListLogic } from './sessionsListLogic'
import type { OpenSessionRead } from './sessionsListLogic'

export type SessionCellRead = 'titles' | 'people'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sessionCellsLogicValues {
    items: SessionListItemApi[] // sessionsListLogic
    people: ReadonlyMap<string, TraceCellLoad<TracePersonApi | null>>
    titles: ReadonlyMap<string, TraceCellLoad<SessionPreviewApi>>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sessionCellsLogicActions {
    loadSessionsPageFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    } // sessionsListLogic
    loadSessionsPageSuccess: (
        page: SessionListApi,
        payload?: AiObservabilitySessionsListParams | undefined
    ) => {
        page: SessionListApi
        payload?: AiObservabilitySessionsListParams
    } // sessionsListLogic
    lookUpSessionSuccess: (
        sessionLookUp: OpenSessionRead,
        payload?: string | undefined
    ) => {
        payload?: string
        sessionLookUp: OpenSessionRead
    } // sessionsListLogic
    reload: () => {
        value: true
    } // sessionsListLogic
    setPageIndex: (pageIndex: number) => {
        pageIndex: number
    } // sessionsListLogic
    cellsFailed: (
        read: SessionCellRead,
        sessionIds: string[]
    ) => {
        read: SessionCellRead
        sessionIds: string[]
    }
    cellsRequested: (
        read: SessionCellRead,
        sessionIds: string[]
    ) => {
        read: SessionCellRead
        sessionIds: string[]
    }
    peopleLoaded: (items: SessionPersonItemApi[]) => {
        items: SessionPersonItemApi[]
    }
    titlesLoaded: (items: SessionPreviewApi[]) => {
        items: SessionPreviewApi[]
    }
}

export type sessionCellsLogicType = MakeLogicType<sessionCellsLogicValues, sessionCellsLogicActions>

/** The title and person of each session on the list, keyed by session id. */
export const sessionCellsLogic = kea<sessionCellsLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'sessions', 'sessionCellsLogic']),
    connect(() => ({
        values: [sessionsListLogic, ['items']],
        actions: [
            sessionsListLogic,
            ['loadSessionsPageSuccess', 'loadSessionsPageFailure', 'setPageIndex', 'reload', 'lookUpSessionSuccess'],
        ],
    })),
    actions({
        cellsRequested: (read: SessionCellRead, sessionIds: string[]) => ({ read, sessionIds }),
        cellsFailed: (read: SessionCellRead, sessionIds: string[]) => ({ read, sessionIds }),
        titlesLoaded: (items: SessionPreviewApi[]) => ({ items }),
        peopleLoaded: (items: SessionPersonItemApi[]) => ({ items }),
    }),
    reducers({
        titles: [
            noEntries<TraceCellLoad<SessionPreviewApi>>(),
            {
                cellsRequested: (state, { read, sessionIds }) =>
                    read === 'titles' ? withRequested(state, sessionIds) : state,
                cellsFailed: (state, { read, sessionIds }) =>
                    read === 'titles' ? withFailed(state, sessionIds) : state,
                titlesLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.sessionId, item])
                    ),
            },
        ],
        people: [
            noEntries<TraceCellLoad<TracePersonApi | null>>(),
            {
                cellsRequested: (state, { read, sessionIds }) =>
                    read === 'people' ? withRequested(state, sessionIds) : state,
                cellsFailed: (state, { read, sessionIds }) =>
                    read === 'people' ? withFailed(state, sessionIds) : state,
                peopleLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.sessionId, item.person])
                    ),
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const readCells = createCellReader<SessionListItemApi, SessionCellRead, { sessionId: string }>({
            cache,
            idOf: (row) => row.id,
            itemIdOf: (item) => item.sessionId,
            requested: actions.cellsRequested,
            failed: actions.cellsFailed,
        })

        const readRows = async (rows: SessionListItemApi[], refresh: boolean): Promise<void> => {
            const projectId = String(ApiConfig.getCurrentProjectId())
            await Promise.all([
                readCells(
                    'titles',
                    rowsToRead(rows, values.titles, refresh),
                    (rows) =>
                        aiObservabilitySessionsPreviewsCreate(projectId, { session_ids: rows.map((row) => row.id) }),
                    (items) => actions.titlesLoaded(items)
                ),
                readCells(
                    'people',
                    rowsToRead(rows, values.people, refresh),
                    (rows) =>
                        aiObservabilitySessionsPeopleCreate(projectId, { session_ids: rows.map((row) => row.id) }),
                    (items) => actions.peopleLoaded(items)
                ),
            ])
        }

        return {
            // A reload shows the first page again once it lands, and its cells are read again with it.
            reload: () => {
                cache.refreshOnNextPage = true
            },
            loadSessionsPageFailure: () => {
                cache.refreshOnNextPage = false
            },
            loadSessionsPageSuccess: async () => {
                const refresh = !!cache.refreshOnNextPage
                cache.refreshOnNextPage = false
                await readRows(values.items, refresh)
            },
            setPageIndex: () => readRows(values.items, false),
            lookUpSessionSuccess: async ({ sessionLookUp }) => {
                if (sessionLookUp?.status === 'ready') {
                    await readRows([sessionLookUp.session], false)
                }
            },
        }
    }),
])
