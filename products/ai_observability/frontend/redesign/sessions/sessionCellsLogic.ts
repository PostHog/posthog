export type sessionCellsLogicType = MakeLogicType<sessionCellsLogicValues, sessionCellsLogicActions>

/** The title and person of each session, read by the session's first trace id. */
export const sessionCellsLogic = kea<sessionCellsLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'sessions', 'sessionCellsLogic']),
    connect(() => ({
        values: [sessionsListLogic, ['items']],
        actions: [
            sessionsListLogic,
            ['loadSessionsPageSuccess', 'loadSessionsPageFailure', 'setPageIndex', 'reload', 'sessionLookedUp'],
        ],
    })),
    actions({
        cellsRequested: (read: SessionCellRead, traceIds: string[]) => ({ read, traceIds }),
        cellsFailed: (read: SessionCellRead, traceIds: string[]) => ({ read, traceIds }),
        titlesLoaded: (items: TracePreviewApi[]) => ({ items }),
        peopleLoaded: (items: TracePersonItemApi[]) => ({ items }),
    }),
    reducers({
        titles: [
            noEntries<TraceCellLoad<TracePreviewApi>>(),
            {
                cellsRequested: (state, { read, traceIds }) =>
                    read === 'titles' ? withRequested(state, traceIds) : state,
                cellsFailed: (state, { read, traceIds }) => (read === 'titles' ? withFailed(state, traceIds) : state),
                titlesLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.traceId, item])
                    ),
            },
        ],
        people: [
            noEntries<TraceCellLoad<TracePersonApi | null>>(),
            {
                cellsRequested: (state, { read, traceIds }) =>
                    read === 'people' ? withRequested(state, traceIds) : state,
                cellsFailed: (state, { read, traceIds }) => (read === 'people' ? withFailed(state, traceIds) : state),
                peopleLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.traceId, item.person])
                    ),
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        // A row in flight is never asked for twice, so a failure only ever settles the rows it was asked for.
        const rowsToRead = (
            rows: SessionListItemApi[],
            loads: ReadonlyMap<string, TraceCellLoad<unknown>>,
            refresh: boolean
        ): SessionListItemApi[] =>
            rows.filter((row) => {
                const status = loads.get(row.firstTraceId)?.status
                return status !== 'loading' && (refresh || status !== 'ready')
            })

        const readCells = createCellReader<SessionListItemApi, SessionCellRead>({
            cache,
            idOf: (row) => row.firstTraceId,
            requested: actions.cellsRequested,
            failed: actions.cellsFailed,
        })

        const readRows = async (rows: SessionListItemApi[], refresh: boolean): Promise<void> => {
            const projectId = String(ApiConfig.getCurrentProjectId())
            await Promise.all([
                readCells(
                    'titles',
                    rowsToRead(rows, values.titles, refresh),
                    (rows) =>
                        aiObservabilityTracesPreviewsCreate(projectId, {
                            trace_ids: rows.map((row) => row.firstTraceId),
                        }),
                    (items) => actions.titlesLoaded(items)
                ),
                readCells(
                    'people',
                    rowsToRead(rows, values.people, refresh),
                    (rows) => aiObservabilityTracesPeopleCreate(projectId, peopleRequest(rows)),
                    (items) => actions.peopleLoaded(items)
                ),
            ])
        }

        return {
            // A reload shows the first page again once it lands, and its cells are read again with it.
            reload: () => {
                cache.refreshOnNextPage = true
            },
            loadSessionsPageFailure: () => {
                cache.refreshOnNextPage = false
            },
            loadSessionsPageSuccess: async () => {
                const refresh = !!cache.refreshOnNextPage
                cache.refreshOnNextPage = false
                await readRows(values.items, refresh)
            },
            setPageIndex: () => readRows(values.items, false),
            sessionLookedUp: ({ session }) => readRows([session], false),
        }
    }),
])
