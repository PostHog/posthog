export interface SessionPageLogicProps {
    sessionId: string
}

export type SessionPageStatus = 'loading' | 'ready' | LoadFailure

type SessionRead = { status: 'loading' } | { status: 'ready'; session: SessionListItemApi } | { status: LoadFailure }

const LOADING: TraceCellLoad<never> = { status: 'loading' }

function onlyItemLoad<Item, Value>(
    result: { value: { items: Item[] } } | { failure: LoadFailure },
    toValue: (item: Item) => Value
): TraceCellLoad<Value> {
    const item = 'value' in result ? result.value.items[0] : undefined
    return item ? { status: 'ready', value: toValue(item) } : { status: 'error' }
}

