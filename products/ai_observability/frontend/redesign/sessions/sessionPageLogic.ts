export type sessionPageLogicType = MakeLogicType<
    sessionPageLogicValues,
    sessionPageLogicActions,
    SessionPageLogicProps,
    sessionPageLogicMeta
>

export const sessionPageLogic: LogicWrapper<sessionPageLogicType> = kea<sessionPageLogicType>([
    props({} as SessionPageLogicProps),
    key((props) => props.sessionId),
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'sessions', 'sessionPageLogic', key]),
    actions({
        reload: true,
    }),
    // Each read settles into its own failure, which the page shows in place, so none of them throws.
    loaders(({ props, values }) => ({
        sessionRead: [
            LOADING as SessionRead,
            {
                loadSession: async (_: void, breakpoint): Promise<SessionRead> => {
                    const result = await readSession(props.sessionId, values.timestamp)
                    breakpoint()
                    return 'failure' in result ? { status: result.failure } : { status: 'ready', session: result.value }
                },
            },
        ],
        title: [
            LOADING as TraceCellLoad<SessionPreviewApi>,
            {
                loadTitle: async (_: void, breakpoint): Promise<TraceCellLoad<SessionPreviewApi>> => {
                    const result = await readOrFailure(
                        aiObservabilitySessionsPreviewsCreate(String(ApiConfig.getCurrentProjectId()), {
                            session_ids: [props.sessionId],
                        })
                    )
                    breakpoint()
                    return onlyItemLoad(result, (item) => item)
                },
            },
        ],
        person: [
            LOADING as TraceCellLoad<TracePersonApi | null>,
            {
                loadPerson: async (_: void, breakpoint): Promise<TraceCellLoad<TracePersonApi | null>> => {
                    const result = await readOrFailure(
                        aiObservabilitySessionsPeopleCreate(String(ApiConfig.getCurrentProjectId()), {
                            session_ids: [props.sessionId],
                        })
                    )
                    breakpoint()
                    return onlyItemLoad(result, (item) => item.person)
                },
            },
        ],
    })),
    selectors({
        status: [
            (s) => [s.sessionRead, s.sessionReadLoading],
            (sessionRead: SessionRead, sessionReadLoading: boolean): SessionPageStatus =>
                sessionReadLoading ? 'loading' : sessionRead.status,
        ],
        session: [
            (s) => [s.sessionRead],
            (sessionRead: SessionRead): SessionListItemApi | null =>
                sessionRead.status === 'ready' ? sessionRead.session : null,
        ],
        timestamp: [
            () => [router.selectors.location],
            (location: { search: string }): string | null => sessionTimestampHint(location.search),
        ],
        sessionsHref: [
            () => [router.selectors.searchParams],
            (searchParams: Record<string, unknown>): string =>
                shellHref(urls.aiObservabilitySessions(), listPageLinkParams(searchParams)),
        ],
    }),
    listeners(({ actions }) => ({
        reload: () => {
            actions.loadSession()
            actions.loadTitle()
            actions.loadPerson()
        },
    })),
    afterMount(({ actions }) => {
        actions.reload()
    }),
])
