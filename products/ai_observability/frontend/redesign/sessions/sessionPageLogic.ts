import {
    MakeLogicType,
    LogicWrapper,
    actions,
    afterMount,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
    selectors,
} from 'kea'
import { router } from 'kea-router'

import { ApiConfig } from 'lib/api'
import { urls } from 'scenes/urls'

import { Breadcrumb } from '~/types'

import type { SessionListItemApi, TracePersonApi, TracePreviewApi } from '../../generated/api.schemas'
import type { TraceCellLoad } from '../shared/cellLoads'
import { readOrFailure } from '../shared/readOrFailure'
import { SESSION_TIMESTAMP_PARAM, shellHref, shellLinkParams } from '../shell/shellNavigation'
import { rawSearchParam } from '../trace/rawSearchParam'
import type { LoadFailure } from '../trace/types'
import { readSessionPeople, readSessionTitles } from './sessionCellReads'
import { readSession } from './sessionLookup'

export interface SessionPageLogicProps {
    sessionId: string
}

export type SessionPageStatus = 'loading' | 'ready' | LoadFailure

const LOADING: TraceCellLoad<never> = { status: 'loading' }

function onlyItemLoad<Item, Value>(
    result: { value: { items: Item[] } } | { failure: LoadFailure },
    toValue: (item: Item) => Value
): TraceCellLoad<Value> {
    const item = 'value' in result ? result.value.items[0] : undefined
    return item ? { status: 'ready', value: toValue(item) } : { status: 'error' }
}

function titleOf(status: SessionPageStatus, title: TraceCellLoad<TracePreviewApi>): string | null {
    if (status !== 'ready') {
        return status === 'loading' ? null : 'Session'
    }
    if (title.status === 'loading') {
        return null
    }
    return (title.status === 'ready' && title.value.input) || 'Untitled session'
}

