export type sessionPageLogicType = MakeLogicType<
    sessionPageLogicValues,
    sessionPageLogicActions,
    SessionPageLogicProps,
    sessionPageLogicMeta
>

export const sessionPageLogic: LogicWrapper<sessionPageLogicType> = kea<sessionPageLogicType>([
    props({} as SessionPageLogicProps),
    key((props) => props.sessionId),
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'sessions', 'sessionPageLogic', key]),
    actions({
        loadSession: true,
        sessionLoaded: (session: SessionListItemApi) => ({ session }),
        sessionLoadFailed: (failure: LoadFailure) => ({ failure }),
        titleRead: (title: TraceCellLoad<TracePreviewApi>) => ({ title }),
        personRead: (person: TraceCellLoad<TracePersonApi | null>) => ({ person }),
    }),
    reducers({
        status: [
            'loading' as SessionPageStatus,
            {
                loadSession: () => 'loading',
                sessionLoaded: () => 'ready',
                sessionLoadFailed: (_, { failure }) => failure,
            },
        ],
        session: [
            null as SessionListItemApi | null,
            {
                sessionLoaded: (_, { session }) => session,
                sessionLoadFailed: () => null,
            },
        ],
        title: [LOADING as TraceCellLoad<TracePreviewApi>, { titleRead: (_, { title }) => title }],
        person: [LOADING as TraceCellLoad<TracePersonApi | null>, { personRead: (_, { person }) => person }],
    }),
    selectors({
        notFound: [(s) => [s.status], (status: SessionPageStatus): boolean => status === 'not_found'],
        sessionsHref: [
            () => [router.selectors.searchParams],
            (searchParams: Record<string, unknown>): string =>
                shellHref(urls.aiObservabilitySessions(), shellLinkParams(searchParams)),
        ],
        breadcrumbs: [
            (s, p) => [s.status, s.title, s.sessionsHref, router.selectors.searchParams, p.sessionId],
            (
                status: SessionPageStatus,
                title: TraceCellLoad<TracePreviewApi>,
                sessionsHref: string,
                searchParams: Record<string, unknown>,
                sessionId: string
            ): Breadcrumb[] => {
                const name = titleOf(status, title)
                return [
                    {
                        key: 'llm_analytics',
                        name: 'AI observability',
                        path: shellHref(urls.aiObservabilityDashboard(), shellLinkParams(searchParams)),
                        iconType: 'llm_analytics',
                    },
                    { key: 'AIObservabilitySessions', name: 'Sessions', path: sessionsHref, iconType: 'llm_analytics' },
                    {
                        key: ['AIObservabilitySession', sessionId],
                        name,
                        iconType: name === null ? 'loading' : 'llm_analytics',
                    },
                ]
            },
        ],
    }),
    listeners(({ actions, props, cache }) => ({
        loadSession: async () => {
            const result = await readSession(
                props.sessionId,
                rawSearchParam(router.values.location.search, SESSION_TIMESTAMP_PARAM)
            )
            if (cache.disposables.isDisposed) {
                return
            }
            if ('failure' in result) {
                actions.sessionLoadFailed(result.failure)
            } else {
                actions.sessionLoaded(result.value)
            }
        },
        sessionLoaded: async ({ session }) => {
            const projectId = String(ApiConfig.getCurrentProjectId())
            const [titles, people] = await Promise.all([
                readOrFailure(readSessionTitles(projectId, [session])),
                readOrFailure(readSessionPeople(projectId, [session])),
            ])
            if (cache.disposables.isDisposed) {
                return
            }
            actions.titleRead(onlyItemLoad(titles, (item) => item))
            actions.personRead(onlyItemLoad(people, (item) => item.person))
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSession()
    }),
])
