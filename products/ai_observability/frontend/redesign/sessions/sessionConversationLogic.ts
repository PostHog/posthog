export const SESSION_TURNS_PAGE_SIZE = 20
export const SESSION_TURNS_LIST: TraceDrawerListId = 'session-turns'

export interface SessionConversationLogicProps {
    sessionId: string
    /** When the session's first turn happened, as its link carries it, so a session older than the AI events retention still reads. */
    timestamp: string | null
    /** A turn to open the conversation on, instead of the first. */
    aroundTraceId: string | null
}

export type ConversationPageDirection = 'first' | 'older' | 'newer'

export type ConversationPagePosition = Pick<
    AiObservabilitySessionsTurnsRetrieveParams,
    'cursor' | 'before_cursor' | 'around'
>

export interface ConversationPageRequest {
    direction: ConversationPageDirection
    position: ConversationPagePosition
}

function mergedRows(
    loaded: ReadonlyMap<string, SessionTurnApi>,
    page: SessionTurnApi[],
    direction: ConversationPageDirection
): ReadonlyMap<string, SessionTurnApi> {
    const entries = page.map((row): [string, SessionTurnApi] => [row.id, row])
    if (direction === 'first') {
        return new Map(entries)
    }
    return direction === 'older' ? new Map([...entries, ...loaded]) : new Map([...loaded, ...entries])
}

function toRow(row: SessionTurnApi): TraceListRow {
    return {
        traceId: row.id,
        timestamp: row.createdAt,
        stepId: null,
        overview: row,
        defaultStepId: row.defaultNodeId ?? undefined,
    }
}

function edgeOf(
    direction: ConversationPageDirection,
    cursor: string | null,
    pageRequest: ConversationPageRequest | null,
    pageLoading: boolean,
    pageFailure: LoadFailure | null
): ConversationEdge {
    if (pageRequest?.direction === direction && (pageLoading || pageFailure)) {
        return pageLoading ? 'loading' : 'failed'
    }
    if (!cursor) {
        return 'end'
    }
    return pageLoading ? 'waiting' : 'more'
}

function statusOf(
    firstPageLoaded: boolean,
    pageRequest: ConversationPageRequest | null,
    pageFailure: LoadFailure | null
): ConversationStatus {
    if (pageFailure && pageRequest?.direction === 'first') {
        return pageFailure
    }
    return firstPageLoaded ? 'ready' : 'loading'
}

