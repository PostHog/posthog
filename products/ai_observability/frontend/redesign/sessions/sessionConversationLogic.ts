export const sessionConversationLogic: LogicWrapper<sessionConversationLogicType> = kea<sessionConversationLogicType>([
    props({} as SessionConversationLogicProps),
    key((props) => props.sessionId),
    path((key) => [
        'products',
        'ai_observability',
        'frontend',
        'redesign',
        'sessions',
        'sessionConversationLogic',
        key,
    ]),
    connect(() => ({
        values: [traceDrawerLogic({ listId: SESSION_TURNS_LIST }), ['openTraceId']],
        actions: [traceDrawerLogic({ listId: SESSION_TURNS_LIST }), ['openRow', 'stepTo']],
    })),
    actions({
        reload: true,
        loadOlder: true,
        loadNewer: true,
        openTurn: (turnId: string, stepId: string) => ({ turnId, stepId }),
        retrySides: true,
        sidesRequested: (traceIds: string[]) => ({ traceIds }),
        sidesFailed: (traceIds: string[]) => ({ traceIds }),
        sidesLoaded: (items: TurnSides[]) => ({ items }),
    }),
    loaders(({ cache, props }) => ({
        page: [
            null as SessionTurnPageApi | null,
            {
                loadConversationPage: async (
                    { position }: ConversationPageRequest,
                    breakpoint
                ): Promise<SessionTurnPageApi> => {
                    cache.pageRequestedAt = performance.now()
                    return readAbortablePage(
                        cache,
                        (signal) =>
                            aiObservabilitySessionsTurnsRetrieve(
                                String(ApiConfig.getCurrentProjectId()),
                                encodeTraceIdSegment(props.sessionId),
                                {
                                    ...position,
                                    limit: SESSION_TURNS_PAGE_SIZE,
                                    ...(props.timestamp && { timestamp_hint: props.timestamp }),
                                },
                                { signal }
                            ),
                        breakpoint
                    )
                },
            },
        ],
    })),
    reducers({
        loadedRows: [
            noEntries<SessionTurnApi>(),
            {
                loadConversationPageSuccess: (loaded, { page, payload }) =>
                    payload ? mergedRows(loaded, page.items, payload.direction) : loaded,
            },
        ],
        sides: [
            noEntries<TraceCellLoad<TraceTurnApi | null>>(),
            {
                sidesRequested: (state, { traceIds }) => withRequested(state, traceIds),
                sidesFailed: (state, { traceIds }) => withFailed(state, traceIds),
                sidesLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.traceId, item.turn])
                    ),
            },
        ],
        olderCursor: [
            null as string | null,
            {
                loadConversationPageSuccess: (cursor, { page, payload }) =>
                    payload?.direction === 'newer' ? cursor : page.previousCursor,
            },
        ],
        newerCursor: [
            null as string | null,
            {
                loadConversationPageSuccess: (cursor, { page, payload }) =>
                    payload?.direction === 'older' ? cursor : page.nextCursor,
            },
        ],
        firstPageLoaded: [
            false,
            {
                loadConversationPageSuccess: (loaded, { payload }) => loaded || payload?.direction === 'first',
            },
        ],
        pageRequest: [
            null as ConversationPageRequest | null,
            {
                loadConversationPage: (_, request) => request,
            },
        ],
        pageFailure: [
            null as LoadFailure | null,
            {
                loadConversationPage: () => null,
                loadConversationPageFailure: (_, { errorObject }) => toLoadFailure(errorObject),
            },
        ],
    }),
    selectors({
        turnRows: [
            (s) => [s.loadedRows],
            (loadedRows: ReadonlyMap<string, SessionTurnApi>): SessionTurnApi[] => [...loadedRows.values()],
        ],
        // Kept apart from the open turn, so a step of the drawer rebuilds no turn.
        turns: [
            (s) => [s.turnRows, s.sides],
            (turnRows: SessionTurnApi[], sides: CellLoads<TraceTurnApi | null>): ConversationTurn[] =>
                conversationTurns(turnRows, sides),
        ],
        status: [
            (s) => [s.firstPageLoaded, s.pageRequest, s.pageFailure],
            (
                firstPageLoaded: boolean,
                pageRequest: ConversationPageRequest | null,
                pageFailure: LoadFailure | null
            ): ConversationStatus => statusOf(firstPageLoaded, pageRequest, pageFailure),
        ],
        rows: [(s) => [s.turnRows], (turnRows: SessionTurnApi[]): TraceListRow[] => turnRows.map(toRow)],
        olderEdge: [
            (s) => [s.olderCursor, s.pageRequest, s.pageLoading, s.pageFailure],
            (
                cursor: string | null,
                pageRequest: ConversationPageRequest | null,
                pageLoading: boolean,
                pageFailure: LoadFailure | null
            ): ConversationEdge => edgeOf('older', cursor, pageRequest, pageLoading, pageFailure),
        ],
        newerEdge: [
            (s) => [s.newerCursor, s.pageRequest, s.pageLoading, s.pageFailure],
            (
                cursor: string | null,
                pageRequest: ConversationPageRequest | null,
                pageLoading: boolean,
                pageFailure: LoadFailure | null
            ): ConversationEdge => edgeOf('newer', cursor, pageRequest, pageLoading, pageFailure),
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        // The drawer steps through the loaded turns only, so the last one open brings in the page after it. Earlier
        // turns load only on a step up: they go above the reader, and would move the turn they opened.
        const loadPastOpenTurn = (): void => {
            const lastRow = values.rows[values.rows.length - 1]
            if (lastRow && lastRow.traceId === values.openTraceId && values.newerEdge === 'more') {
                actions.loadNewer()
            }
        }

        const readSides = createCellReader<SessionTurnApi, 'sides', TurnSides>({
            cache,
            idOf: (row) => row.id,
            itemIdOf: (item) => item.traceId,
            requested: (_, traceIds) => actions.sidesRequested(traceIds),
            failed: (_, traceIds) => actions.sidesFailed(traceIds),
        })

        const readSidesOf = async (rows: SessionTurnApi[], refresh: boolean): Promise<void> => {
            const projectId = String(ApiConfig.getCurrentProjectId())
            const toRead = rowsToRead(rows, values.sides, refresh)
            if (toRead.length === 0) {
                return
            }
            // Marked before the first batch goes out, so a second retry asks for no batch that still waits its turn.
            actions.sidesRequested(toRead.map((row) => row.id))
            // One batch at a time: a retry of every failed turn would otherwise run past the query concurrency limit.
            for (const batch of turnSidesBatches(toRead)) {
                await readSides(
                    'sides',
                    batch,
                    async (batchRows) => {
                        const { items } = await aiObservabilityTracesTurnsCreate(projectId, pageRequest(batchRows), {
                            signal: cache.sidesSignal,
                        })
                        return { items: turnSidesOfRows(batchRows, items) }
                    },
                    actions.sidesLoaded
                )
                if (cache.disposables.isDisposed) {
                    return
                }
            }
        }

        return {
            [router.actionTypes.locationChanged]: () => {
                // Closing the drawer or opening another turn takes back a step up that is still loading earlier turns.
                if (values.openTraceId !== cache.openBeforeTraceId) {
                    cache.openBeforeTraceId = null
                }
                loadPastOpenTurn()
            },
            stepTo: ({ direction }) => {
                const firstRow = values.rows[0]
                // A failed edge counts, or the drawer's step up would stay enabled and do nothing after a failed read.
                const canLoadOlder = values.olderEdge === 'more' || values.olderEdge === 'failed'
                if (direction === 'previous' && firstRow?.traceId === values.openTraceId && canLoadOlder) {
                    cache.openBeforeTraceId = firstRow.traceId
                    actions.loadOlder()
                }
            },
            loadConversationPageFailure: () => {
                cache.openBeforeTraceId = null
            },
            reload: () => {
                // The reload aborts an earlier page a step up asked for, and that step must not open a turn later.
                cache.openBeforeTraceId = null
                actions.loadConversationPage({
                    direction: 'first',
                    position: props.aroundTraceId ? { around: props.aroundTraceId } : {},
                })
            },
            loadOlder: () => {
                if (values.olderCursor && !values.pageLoading) {
                    actions.loadConversationPage({
                        direction: 'older',
                        position: { before_cursor: values.olderCursor },
                    })
                }
            },
            loadNewer: () => {
                if (values.newerCursor && !values.pageLoading) {
                    actions.loadConversationPage({ direction: 'newer', position: { cursor: values.newerCursor } })
                }
            },
            retrySides: () => readSidesOf(values.turnRows, false),
            loadConversationPageSuccess: async ({ page, payload }) => {
                if (payload?.direction === 'first' && page.items.length > 0 && !cache.conversationLoadedSent) {
                    cache.conversationLoadedSent = true
                    sessionsTracking.conversationLoaded({
                        turnsWaitMs: Math.round(performance.now() - cache.pageRequestedAt),
                        turnCount: page.items.length,
                        openedAround: props.aroundTraceId !== null,
                    })
                }
                if (payload?.direction === 'older' && cache.openBeforeTraceId) {
                    const index = values.rows.findIndex((row) => row.traceId === cache.openBeforeTraceId)
                    cache.openBeforeTraceId = null
                    if (index > 0) {
                        actions.openRow(values.rows[index - 1])
                    }
                }
                loadPastOpenTurn()
                // A reload reads the messages of turns already on screen again, as the lists read their cells again.
                await readSidesOf(page.items, payload?.direction === 'first')
            },
            openTurn: ({ turnId, stepId }) => {
                const row = values.rows.find((candidate) => candidate.traceId === turnId)
                if (row) {
                    actions.openRow({ ...row, stepId })
                }
            },
        }
    }),
    afterMount(({ actions, cache }) => {
        const sidesRequests = new AbortController()
        cache.sidesSignal = sidesRequests.signal
        // Leaving a session frees the query slots of the messages still loading. A hidden tab keeps them.
        cache.disposables.add(() => () => sidesRequests.abort(), 'sidesRequests', { pauseOnPageHidden: false })
        actions.reload()
    }),
])
