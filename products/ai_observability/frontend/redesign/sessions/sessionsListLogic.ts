/** How far the open session has been read: from a list page, or on its own when no loaded page lists it. */
export type OpenSessionRead =
    | { sessionId: string; status: 'loading' }
    | { sessionId: string; status: 'ready'; session: SessionListItemApi }
    | { sessionId: string; status: LoadFailure }

export type OpenSessionStatus = 'none' | OpenSessionRead['status']

type ListUrl = ReturnType<typeof currentUrlWith>

function narrowsSelection(params: AiObservabilitySessionsListParams | null): boolean {
    return !!(params?.properties || params?.search || params?.filter_test_accounts)
}

// Opening a session closes the trace drawer of the session before it. The link carries when the session started, so a
// session older than the AI events retention still reads.
function withOpenSession(url: RouterUrl, session: SessionListItemApi | null): ListUrl {
    const closedDrawer = Object.fromEntries(TRACE_DRAWER_PARAMS.map((name) => [name, undefined]))
    return currentUrlWith(url, { ...closedDrawer, ...openSessionParams(session) })
}

function openSessionParams(session: SessionListItemApi | null): Record<string, string | undefined> {
    return { [SESSION_PARAM]: session?.id, [SESSION_TIMESTAMP_PARAM]: session?.firstSeen }
}

function isSessionsPath(pathname: string): boolean {
    return removeProjectIdIfPresent(pathname) === SESSIONS_LIST_FILTERS.path
}

