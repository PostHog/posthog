export const sessionsListLogic = kea<sessionsListLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'sessions', 'sessionsListLogic']),
    connect(() => ({
        values: [
            listFiltersLogic(SESSIONS_LIST_FILTERS),
            ['filters'],
            shellScopeLogic,
            ['dateFrom', 'dateTo'],
            filterTestAccountsDefaultsLogic,
            ['filterTestAccountsDefault'],
            featureFlagLogic,
            ['featureFlags'],
            router,
            ['location'],
        ],
    })),
    actions({
        selectionChanged: true,
        reload: true,
        showPreviousPage: true,
        showNextPage: true,
        setPageIndex: (pageIndex: number) => ({ pageIndex }),
        openSession: (sessionId: string | null) => ({ sessionId }),
        findOpenSession: true,
        sessionListed: (session: SessionListItemApi) => ({ session }),
        lookUpSession: (sessionId: string) => ({ sessionId }),
        sessionLookedUp: (sessionId: string, session: SessionListItemApi) => ({ sessionId, session }),
        sessionLookUpFailed: (sessionId: string, failure: LoadFailure) => ({ sessionId, failure }),
    }),
    loaders(({ cache }) => ({
        page: [
            null as SessionListApi | null,
            {
                loadSessionsPage: async (
                    params: AiObservabilitySessionsListParams,
                    breakpoint
                ): Promise<SessionListApi> => {
                    cache.pageRequestedAt = performance.now()
                    return readAbortablePage(
                        cache,
                        (signal) =>
                            aiObservabilitySessionsList(String(ApiConfig.getCurrentProjectId()), params, { signal }),
                        breakpoint
                    )
                },
            },
        ],
    })),
    reducers({
        pages: [
            [] as SessionListApi[],
            {
                selectionChanged: () => [],
                loadSessionsPageSuccess: (pages, { page, payload }) => appendedPages(pages, page, payload),
            },
        ],
        pageIndex: [
            0,
            {
                selectionChanged: () => 0,
                setPageIndex: (_, { pageIndex }) => pageIndex,
                loadSessionsPageSuccess: (pageIndex, { payload }) => pageIndexAfterLoad(pageIndex, payload),
            },
        ],
        pagesParams: [
            null as AiObservabilitySessionsListParams | null,
            {
                selectionChanged: () => null,
                loadSessionsPageSuccess: (current, { payload }) => firstPageParams(current, payload),
            },
        ],
        pageFailed: [
            false,
            {
                loadSessionsPage: () => false,
                loadSessionsPageFailure: () => true,
            },
        ],
        // Kept across list reloads, so a filter that takes the open session off the list leaves it open.
        openSessionRead: [
            null as OpenSessionRead | null,
            {
                sessionListed: (_, { session }) => ({ sessionId: session.id, status: 'ready', session }),
                lookUpSession: (_, { sessionId }) => ({ sessionId, status: 'loading' }),
                sessionLookedUp: (read, { sessionId, session }) =>
                    read?.sessionId === sessionId ? { sessionId, status: 'ready', session } : read,
                sessionLookUpFailed: (read, { sessionId, failure }) =>
                    read?.sessionId === sessionId ? { sessionId, status: failure } : read,
            },
        ],
    }),
    selectors({
        searchEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.LLM_OBSERVABILITY_TRACE_SEARCH],
        ],
        // The switch shows this and every request sends it, so the rows always match the switch.
        filterTestAccounts: [
            (s) => [s.filters, s.filterTestAccountsDefault],
            (filters: ListFilters, filterTestAccountsDefault: boolean): boolean =>
                filters.filterTestAccounts ?? filterTestAccountsDefault,
        ],
        requestParams: [
            (s) => [s.filters, s.dateFrom, s.dateTo, s.filterTestAccounts, s.searchEnabled],
            (
                filters: ListFilters,
                dateFrom: string,
                dateTo: string | null,
                filterTestAccounts: boolean,
                searchEnabled: boolean
            ): AiObservabilitySessionsListParams => ({
                ...listRequestParams(filters, { dateFrom, dateTo, filterTestAccounts, searchEnabled }),
                limit: SESSIONS_PAGE_SIZE,
            }),
        ],
        shownPage: [
            (s) => [s.pages, s.pageIndex],
            (pages: SessionListApi[], pageIndex: number): SessionListApi | null => shownPageOf(pages, pageIndex),
        ],
        items: [(s) => [s.shownPage], (shownPage: SessionListApi | null): SessionListItemApi[] => itemsOf(shownPage)],
        canShowPrevious: [
            (s) => [s.pageIndex, s.pageLoading],
            (pageIndex: number, pageLoading: boolean): boolean => canStepBack(pageIndex, pageLoading),
        ],
        canShowNext: [(s) => [s.shownPage], (shownPage: SessionListApi | null): boolean => canStepForward(shownPage)],
        refreshing: [
            (s) => [s.pageLoading, s.pages],
            (pageLoading: boolean, pages: SessionListApi[]): boolean => isRefreshing(pageLoading, pages),
        ],
        sessionHref: [
            (s) => [s.location, router.selectors.searchParams, router.selectors.hashParams],
            (
                location: RouterUrl['location'],
                searchParams: Record<string, unknown>,
                hashParams: Record<string, unknown>
            ): ((sessionId: string) => string) =>
                (sessionId) =>
                    combineUrl(...withOpenSession({ location, searchParams, hashParams }, sessionId)).url,
        ],
        openSessionId: [
            (s) => [s.location],
            (location: { pathname: string; search: string }): string | null =>
                isSessionsPath(location.pathname) ? rawSearchParam(location.search, SESSION_PARAM) : null,
        ],
        openItem: [
            (s) => [s.openSessionId, s.openSessionRead],
            (openSessionId: string | null, read: OpenSessionRead | null): SessionListItemApi | null =>
                read?.status === 'ready' && read.sessionId === openSessionId ? read.session : null,
        ],
        openSessionStatus: [
            (s) => [s.openSessionId, s.openSessionRead],
            (openSessionId: string | null, read: OpenSessionRead | null): OpenSessionStatus =>
                openSessionId === null ? 'none' : read?.sessionId === openSessionId ? read.status : 'loading',
        ],
        state: [
            (s) => [s.pages, s.pageFailed, s.pagesParams],
            (
                pages: SessionListApi[],
                pageFailed: boolean,
                pagesParams: AiObservabilitySessionsListParams | null
            ): ListTableState => listStateOf(pages, pageFailed, pagesParams, narrowsSelection),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        findOpenSession: () => {
            const sessionId = values.openSessionId
            if (!sessionId) {
                return
            }
            const listed = values.pages.flatMap((page) => page.items).find((item) => item.id === sessionId)
            if (listed) {
                actions.sessionListed(listed)
            } else if (values.state !== 'loading' && values.openSessionRead?.sessionId !== sessionId) {
                actions.lookUpSession(sessionId)
            }
        },
        lookUpSession: async ({ sessionId }) => {
            const timestamp = rawSearchParam(router.values.location.search, SESSION_TIMESTAMP_PARAM)
            const result = await readOrFailure(
                aiObservabilitySessionsRetrieve(
                    String(ApiConfig.getCurrentProjectId()),
                    encodeTraceIdSegment(sessionId),
                    timestamp ? { timestamp } : undefined
                )
            )
            if ('failure' in result) {
                actions.sessionLookUpFailed(sessionId, result.failure)
            } else {
                actions.sessionLookedUp(sessionId, result.value)
            }
        },
        selectionChanged: () => actions.loadSessionsPage(values.requestParams),
        reload: () => actions.loadSessionsPage(values.requestParams),
        showPreviousPage: () => {
            if (values.canShowPrevious) {
                actions.setPageIndex(values.pageIndex - 1)
            }
        },
        showNextPage: () => {
            const step = nextPageStep(values)
            if (step && 'show' in step) {
                actions.setPageIndex(step.show)
            } else if (step) {
                actions.loadSessionsPage(step.load)
            }
        },
        loadSessionsPageSuccess: ({ page, payload }) => {
            actions.findOpenSession()
            if (!payload || payload.cursor) {
                return
            }
            sessionsTracking.listLoaded({
                rowsWaitMs: Math.round(performance.now() - cache.pageRequestedAt),
                rowCount: page.items.length,
                dateFrom: payload.date_from ?? null,
                searched: !!payload.search,
            })
        },
        loadSessionsPageFailure: () => {
            actions.findOpenSession()
            // With no rows on screen the list shows the error itself.
            if (values.pages.length > 0) {
                lemonToast.error("Couldn't load sessions. Try again.")
            }
        },
        openSession: ({ sessionId }) => {
            if (!isSessionsPath(router.values.location.pathname)) {
                return
            }
            router.actions.replace(...withOpenSession(router.values, sessionId))
        },
    })),
    // Fires on mount with the settled filters, range and open session, then on each change of them.
    subscriptions(({ actions }) => ({
        requestParams: () => actions.selectionChanged(),
        openSessionId: () => actions.findOpenSession(),
    })),
])
