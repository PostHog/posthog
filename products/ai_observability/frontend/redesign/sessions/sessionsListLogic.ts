export const sessionsListLogic = kea<sessionsListLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'sessions', 'sessionsListLogic']),
    connect(() => ({
        values: [
            listFiltersLogic(SESSIONS_LIST_FILTERS),
            ['filters'],
            shellScopeLogic,
            ['dateFrom', 'dateTo'],
            filterTestAccountsDefaultsLogic,
            ['filterTestAccountsDefault'],
            router,
            ['location'],
        ],
    })),
    actions({
        selectionChanged: true,
        reload: true,
        showPreviousPage: true,
        showNextPage: true,
        setPageIndex: (pageIndex: number) => ({ pageIndex }),
        openSession: (sessionId: string | null) => ({ sessionId }),
    }),
    loaders(({ cache }) => ({
        page: [
            null as SessionListApi | null,
            {
                loadSessionsPage: async (
                    params: AiObservabilitySessionsListParams,
                    breakpoint
                ): Promise<SessionListApi> => {
                    const controller = new AbortController()
                    // The next read and the unmount abort this one, so a superseded scan frees its query slot. A
                    // hidden tab keeps it, so coming back shows no failed load.
                    cache.disposables.add(() => () => controller.abort(), 'pageRequest', { pauseOnPageHidden: false })
                    const page = await aiObservabilitySessionsList(String(ApiConfig.getCurrentProjectId()), params, {
                        signal: controller.signal,
                    }).catch((error: unknown) => {
                        // A superseded request must not show its failure over the newer selection.
                        breakpoint()
                        throw error
                    })
                    breakpoint()
                    return page
                },
            },
        ],
    })),
    reducers({
        pages: [
            [] as SessionListApi[],
            {
                selectionChanged: () => [],
                loadSessionsPageSuccess: (pages, { page, payload }) => (payload?.cursor ? [...pages, page] : [page]),
            },
        ],
        pageIndex: [
            0,
            {
                selectionChanged: () => 0,
                setPageIndex: (_, { pageIndex }) => pageIndex,
                loadSessionsPageSuccess: (pageIndex, { payload }) => (payload?.cursor ? pageIndex + 1 : 0),
            },
        ],
        // The params of the first page in memory. A next page reads with them, not with filters typed since.
        pagesParams: [
            null as AiObservabilitySessionsListParams | null,
            {
                selectionChanged: () => null,
                loadSessionsPageSuccess: (current, { payload }) => (payload && !payload.cursor ? payload : current),
            },
        ],
        pageFailed: [
            false,
            {
                loadSessionsPage: () => false,
                loadSessionsPageFailure: () => true,
            },
        ],
    }),
    selectors({
        // The switch shows this and every request sends it, so the rows always match the switch.
        filterTestAccounts: [
            (s) => [s.filters, s.filterTestAccountsDefault],
            (filters: ListFilters, filterTestAccountsDefault: boolean): boolean =>
                filters.filterTestAccounts ?? filterTestAccountsDefault,
        ],
        requestParams: [
            (s) => [s.filters, s.dateFrom, s.dateTo, s.filterTestAccounts],
            (
                filters: ListFilters,
                dateFrom: string,
                dateTo: string | null,
                filterTestAccounts: boolean
            ): AiObservabilitySessionsListParams => ({
                date_from: dateFrom,
                date_to: dateTo ?? undefined,
                properties: filters.propertyFilters.length > 0 ? JSON.stringify(filters.propertyFilters) : undefined,
                filter_test_accounts: filterTestAccounts,
                limit: SESSIONS_PAGE_SIZE,
            }),
        ],
        shownPage: [
            (s) => [s.pages, s.pageIndex],
            (pages: SessionListApi[], pageIndex: number): SessionListApi | null => pages[pageIndex] ?? null,
        ],
        items: [
            (s) => [s.shownPage],
            (shownPage: SessionListApi | null): SessionListItemApi[] => shownPage?.items ?? [],
        ],
        // A page that lands moves the index on from where it was requested, so stepping back meanwhile would undo it.
        canShowPrevious: [
            (s) => [s.pageIndex, s.pageLoading],
            (pageIndex: number, pageLoading: boolean): boolean => pageIndex > 0 && !pageLoading,
        ],
        canShowNext: [(s) => [s.shownPage], (shownPage: SessionListApi | null): boolean => !!shownPage?.nextCursor],
        refreshing: [
            (s) => [s.pageLoading, s.pages],
            (pageLoading: boolean, pages: SessionListApi[]): boolean => pageLoading && pages.length > 0,
        ],
        openSessionId: [
            (s) => [s.location],
            (location: { pathname: string; search: string }): string | null =>
                isSessionsPath(location.pathname) ? rawSearchParam(location.search, SESSION_PARAM) : null,
        ],
        state: [
            (s) => [s.pages, s.pageFailed, s.pagesParams],
            (
                pages: SessionListApi[],
                pageFailed: boolean,
                pagesParams: AiObservabilitySessionsListParams | null
            ): ListTableState => {
                const firstPage = pages[0]
                if (!firstPage) {
                    return pageFailed ? 'error' : 'loading'
                }
                if (firstPage.items.length === 0) {
                    return narrowsSelection(pagesParams) ? 'empty-filtered' : 'empty'
                }
                return 'ready'
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        selectionChanged: () => actions.loadSessionsPage(values.requestParams),
        reload: () => actions.loadSessionsPage(values.requestParams),
        showPreviousPage: () => {
            if (values.canShowPrevious) {
                actions.setPageIndex(values.pageIndex - 1)
            }
        },
        showNextPage: () => {
            const { pages, pageIndex, pagesParams, pageLoading } = values
            if (pages[pageIndex + 1]) {
                actions.setPageIndex(pageIndex + 1)
                return
            }
            const cursor = pages[pageIndex]?.nextCursor
            // A read in flight is either this next page or a first page that replaces the pages.
            if (cursor && pagesParams && !pageLoading) {
                actions.loadSessionsPage({ ...pagesParams, cursor })
            }
        },
        loadSessionsPageFailure: () => {
            // With no rows on screen the list shows the error itself.
            if (values.pages.length > 0) {
                lemonToast.error("Couldn't load sessions. Try again.")
            }
        },
        openSession: ({ sessionId }) => {
            if (!isSessionsPath(router.values.location.pathname)) {
                return
            }
            const dropped = Object.fromEntries(TRACE_DRAWER_PARAMS.map((name) => [name, undefined]))
            router.actions.replace(
                ...currentUrlWith(router.values, { ...dropped, [SESSION_PARAM]: sessionId ?? undefined })
            )
        },
    })),
    // Fires on mount with the settled filters and range, then on each change that must reload the list.
    subscriptions(({ actions }) => ({
        requestParams: () => actions.selectionChanged(),
    })),
])
