export const SESSIONS_PAGE_SIZE = 50

export const SESSIONS_LIST_FILTERS: ListFiltersLogicProps = { listId: 'sessions', path: urls.aiObservabilitySessions() }

/** How far the open session has been read: from a list page, or on its own when no loaded page lists it. */
export type OpenSessionRead =
    | { sessionId: string; status: 'loading' }
    | { sessionId: string; status: 'ready'; session: SessionListItemApi }
    | { sessionId: string; status: LoadFailure }

export type OpenSessionStatus = 'none' | OpenSessionRead['status']

function narrowsSelection(params: AiObservabilitySessionsListParams | null): boolean {
    return !!(params?.properties || params?.search || params?.filter_test_accounts)
}

// Opening a session closes the trace drawer of the session before it and drops the time its link carried.
function withOpenSession(url: RouterUrl, sessionId: string | null): ReturnType<typeof currentUrlWith> {
    const dropped = Object.fromEntries(
        [...TRACE_DRAWER_PARAMS, SESSION_TIMESTAMP_PARAM].map((name) => [name, undefined])
    )
    return currentUrlWith(url, { ...dropped, [SESSION_PARAM]: sessionId ?? undefined })
}

function isSessionsPath(pathname: string): boolean {
    return removeProjectIdIfPresent(pathname) === SESSIONS_LIST_FILTERS.path
}

