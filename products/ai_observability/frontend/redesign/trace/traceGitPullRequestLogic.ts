export type traceGitPullRequestLogicType = MakeLogicType<
    traceGitPullRequestLogicValues,
    traceGitPullRequestLogicActions,
    TraceViewLogicProps,
    traceGitPullRequestLogicMeta
>

export const traceGitPullRequestLogic = kea<traceGitPullRequestLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceGitPullRequestLogic', key]),
    props({} as TraceViewLogicProps),
    key((props) => props.traceId),
    connect((props: TraceViewLogicProps) => ({
        values: [traceViewLogic(props), ['trace'], featureFlagLogic, ['featureFlags']],
    })),
    loaders(({ props }) => ({
        pullRequest: [
            null as TracePullRequestApi | null,
            {
                loadTracePullRequest: async (timestampHint: string): Promise<TracePullRequestApi | null> => {
                    const { pullRequest } = await aiObservabilityTracesPullRequestRetrieve(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        { timestamp_hint: timestampHint }
                    )
                    return pullRequest
                },
            },
        ],
    })),
    selectors({
        pullRequestTimestampHint: [
            (s) => [s.trace, s.featureFlags],
            (trace: TraceApi | null, featureFlags: FeatureFlagsSet): string | null =>
                trace?.git && featureFlags[FEATURE_FLAGS.ENGINEERING_ANALYTICS] ? trace.createdAt : null,
        ],
    }),
    // Flags can arrive after the trace on a deep link, so the read waits for both rather than for either action.
    subscriptions(({ actions }) => ({
        pullRequestTimestampHint: (pullRequestTimestampHint: string | null) => {
            if (pullRequestTimestampHint) {
                actions.loadTracePullRequest(pullRequestTimestampHint)
            }
        },
    })),
])
