import { MakeLogicType, connect, kea, key, listeners, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiConfig } from 'lib/api'
import { exportsLogic } from 'lib/components/ExportButton/exportsLogic'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'

import { ExportedAssetType, ExporterFormat } from '~/types'

import { aiObservabilityTracesExportsCreate, aiObservabilityTracesExportsRetrieve } from '../../generated/api'
import { ExportStatusEnumApi, type TraceExportApi } from '../../generated/api.schemas'
import { encodeTraceIdSegment } from './traceIdSegment'
import { traceViewLogic } from './traceViewLogic'

export interface TraceExportLogicProps {
    traceId: string
    timestampHint: string | null
}

export function toExportedAsset(traceExport: TraceExportApi): ExportedAssetType {
    return {
        id: traceExport.id,
        export_format: ExporterFormat.JSON,
        has_content: traceExport.status === ExportStatusEnumApi.Complete,
        filename: traceExport.filename,
        created_at: traceExport.createdAt,
        expires_after: traceExport.expiresAfter ?? undefined,
        exception: traceExport.status === ExportStatusEnumApi.Failed ? (traceExport.exception ?? undefined) : undefined,
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceExportLogicValues {
    createdAt: string | null // traceViewLogic
    traceExport: TraceExportApi | null
    traceExportLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceExportLogicActions {
    trackExport: (
        exportedAsset: ExportedAssetType,
        fetchLatest?: import('lib/components/ExportButton/exportsLogic').ExportStatusFetcher | undefined
    ) => {
        exportedAsset: ExportedAssetType
        fetchLatest: import('lib/components/ExportButton/exportsLogic').ExportStatusFetcher | undefined
    } // exportsLogic
    exportTrace: () => any
    exportTraceFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    exportTraceSuccess: (
        traceExport: TraceExportApi,
        payload?: any
    ) => {
        traceExport: TraceExportApi
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceExportLogicMeta {
    key: string
}

export type traceExportLogicType = MakeLogicType<
    traceExportLogicValues,
    traceExportLogicActions,
    TraceExportLogicProps,
    traceExportLogicMeta
>

export const traceExportLogic = kea<traceExportLogicType>([
    props({} as TraceExportLogicProps),
    key((props) => props.traceId),
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceExportLogic', key]),
    connect((props: TraceExportLogicProps) => ({
        values: [traceViewLogic(props), ['createdAt']],
        actions: [exportsLogic, ['trackExport']],
    })),
    loaders(({ props, values }) => ({
        traceExport: [
            null as TraceExportApi | null,
            {
                exportTrace: async (): Promise<TraceExportApi> =>
                    await aiObservabilityTracesExportsCreate(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        values.createdAt ? { timestamp_hint: values.createdAt } : {}
                    ),
            },
        ],
    })),
    listeners(({ actions, props }) => ({
        exportTraceSuccess: ({ traceExport }) => {
            if (traceExport.status === ExportStatusEnumApi.Failed) {
                lemonToast.error(traceExport.exception ?? "Couldn't export this trace. Try again.")
                return
            }
            actions.trackExport(toExportedAsset(traceExport), async () =>
                toExportedAsset(
                    await aiObservabilityTracesExportsRetrieve(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        traceExport.id
                    )
                )
            )
            lemonToast.info("Exporting this trace. The file appears in Exports when it's ready.")
        },
    })),
])
