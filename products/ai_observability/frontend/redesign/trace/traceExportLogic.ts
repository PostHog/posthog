export type traceExportLogicType = MakeLogicType<
    traceExportLogicValues,
    traceExportLogicActions,
    TraceExportLogicProps,
    traceExportLogicMeta
>

export const traceExportLogic = kea<traceExportLogicType>([
    props({} as TraceExportLogicProps),
    key((props) => props.traceId),
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceExportLogic', key]),
    connect((props: TraceExportLogicProps) => ({
        values: [traceViewLogic(props), ['createdAt']],
        actions: [exportsLogic, ['trackExport', 'downloadExport']],
    })),
    actions({
        copyTrace: true,
        copyTraceFinished: true,
    }),
    loaders(({ props, values }) => ({
        traceExport: [
            null as TraceExportApi | null,
            {
                exportTrace: async (): Promise<TraceExportApi> =>
                    await aiObservabilityTracesExportsCreate(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        values.createdAt ? { timestamp_hint: values.createdAt } : {}
                    ),
            },
        ],
    })),
    reducers({
        traceCopying: [
            false,
            {
                copyTrace: () => true,
                copyTraceFinished: () => false,
            },
        ],
    }),
    listeners(({ actions, props, values, cache }) => ({
        copyTrace: async () => {
            const controller = new AbortController()
            // The copy keeps running while the tab is hidden, so that switching tabs does not abort it.
            cache.disposables.add(() => () => controller.abort(), 'traceCopy', { pauseOnPageHidden: false })
            const reading = readTraceExportText({
                traceId: props.traceId,
                timestampHint: values.createdAt,
                signal: controller.signal,
            })
            const written = writePendingTextToClipboard(reading.then(({ text }) => text))
            try {
                const [copied, { text, sizeBytes }] = await Promise.all([written, reading])
                if (copied) {
                    lemonToast.info('Copied trace to clipboard')
                    posthog.capture('llma trace export copied', { size_bytes: sizeBytes, fallback: false })
                } else {
                    lemonToast.info('The trace is ready to copy.', {
                        button: {
                            label: 'Copy',
                            action: async () => {
                                if (await copyToClipboard(text, 'trace')) {
                                    posthog.capture('llma trace export copied', {
                                        size_bytes: sizeBytes,
                                        fallback: true,
                                    })
                                }
                            },
                        },
                    })
                }
            } catch (error) {
                if (controller.signal.aborted) {
                    return
                }
                if (error instanceof TraceTooLargeToCopyError) {
                    const exportedAsset = toExportedAsset(error.traceExport)
                    lemonToast.info(
                        `This trace is larger than ${COPY_TRACE_MAX_MEGABYTES} MB, so it can't be copied. Download it as a JSON file instead.`,
                        { button: { label: 'Download', action: () => actions.downloadExport(exportedAsset) } }
                    )
                    trackCopyFailure('too_large')
                } else if (error instanceof TraceExportFailedError) {
                    lemonToast.error(error.message)
                    trackCopyFailure('export_failed')
                } else {
                    lemonToast.error("Couldn't copy this trace. Try again.")
                    trackCopyFailure('error')
                    posthog.captureException(error)
                }
            }
            cache.disposables.dispose('traceCopy')
            actions.copyTraceFinished()
        },
        exportTraceSuccess: ({ traceExport }) => {
            if (traceExport.status === ExportStatusEnumApi.Failed) {
                lemonToast.error(traceExport.exception ?? "Couldn't export this trace. Try again.")
                return
            }
            actions.trackExport(toExportedAsset(traceExport), async () =>
                toExportedAsset(
                    await aiObservabilityTracesExportsRetrieve(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        traceExport.id
                    )
                )
            )
            lemonToast.info("Exporting this trace. The file appears in Exports when it's ready.")
        },
    })),
])
