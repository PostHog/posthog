import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { combineUrl } from 'kea-router'

import { ApiConfig } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { userHasAccess } from 'lib/utils/accessControlUtils'
import { urls } from 'scenes/urls'

import { AccessControlLevel, AccessControlResourceType } from '~/types'

import { aiObservabilityTracesReviewRetrieve, llmAnalyticsReviewQueueItemsDestroy } from '../../generated/api'
import type { TraceReviewStatusApi } from '../../generated/api.schemas'
import { traceReviewsLazyLoaderLogic } from '../../traceReviews/traceReviewsLazyLoaderLogic'
import { encodeTraceIdSegment } from './traceIdSegment'

export interface TraceReviewLogicProps {
    traceId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceReviewLogicValues {
    canEditReviews: boolean
    queueHref: string | null
    removeFromQueueLoading: boolean
    reviewStatus: TraceReviewStatusApi | null
    reviewStatusFailed: boolean
    reviewStatusLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceReviewLogicActions {
    setTraceAsUnreviewed: (traceId: string) => {
        traceId: string
    } // traceReviewsLazyLoaderLogic
    setTraceReview: (review: import('../../traceReviews/types').TraceReview) => {
        review: import('../../traceReviews/types').TraceReview
    } // traceReviewsLazyLoaderLogic
    loadReviewStatus: (_: void) => void
    loadReviewStatusFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadReviewStatusSuccess: (
        reviewStatus: TraceReviewStatusApi,
        payload?: void
    ) => {
        reviewStatus: TraceReviewStatusApi
        payload?: void
    }
    removeFromQueue: () => {
        value: true
    }
    removeFromQueueFailure: () => {
        value: true
    }
    removeFromQueueSuccess: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceReviewLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        queueHref: (reviewStatus: TraceReviewStatusApi | null) => string | null
    }
}

export type traceReviewLogicType = MakeLogicType<
    traceReviewLogicValues,
    traceReviewLogicActions,
    TraceReviewLogicProps,
    traceReviewLogicMeta
>

export const traceReviewLogic = kea<traceReviewLogicType>([
    props({} as TraceReviewLogicProps),
    key((props) => props.traceId),
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceReviewLogic', key]),
    connect(() => ({
        actions: [traceReviewsLazyLoaderLogic, ['setTraceReview', 'setTraceAsUnreviewed']],
    })),
    actions({
        removeFromQueue: true,
        removeFromQueueSuccess: true,
        removeFromQueueFailure: true,
    }),
    loaders(({ props }) => ({
        reviewStatus: [
            null as TraceReviewStatusApi | null,
            {
                loadReviewStatus: async (_: void, breakpoint): Promise<TraceReviewStatusApi> => {
                    const status = await aiObservabilityTracesReviewRetrieve(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId)
                    )
                    breakpoint()
                    return status
                },
            },
        ],
    })),
    reducers({
        reviewStatus: {
            removeFromQueueSuccess: (status) => (status ? { ...status, queue: null } : status),
        },
        reviewStatusFailed: [
            false,
            {
                loadReviewStatusSuccess: () => false,
                loadReviewStatusFailure: () => true,
            },
        ],
        removeFromQueueLoading: [
            false,
            {
                removeFromQueue: () => true,
                removeFromQueueSuccess: () => false,
                removeFromQueueFailure: () => false,
            },
        ],
    }),
    selectors({
        canEditReviews: [
            () => [],
            (): boolean => userHasAccess(AccessControlResourceType.LlmAnalytics, AccessControlLevel.Editor),
        ],
        queueHref: [
            (s) => [s.reviewStatus],
            (reviewStatus: TraceReviewStatusApi | null): string | null =>
                reviewStatus?.queue
                    ? combineUrl(urls.aiObservabilityReviews(), { queue_id: reviewStatus.queue.id }).url
                    : null,
        ],
    }),
    listeners(({ actions, values, props }) => ({
        // The review modal reports a save through onReviewSaved but never a removal, while both pass through the
        // review cache, so the cache is the one signal that covers both. Opening the modal also writes the cache,
        // which costs one extra status read per open.
        setTraceReview: ({ review }) => {
            if (review.trace_id === props.traceId) {
                actions.loadReviewStatus()
            }
        },
        setTraceAsUnreviewed: ({ traceId }) => {
            if (traceId === props.traceId) {
                actions.loadReviewStatus()
            }
        },
        removeFromQueue: async () => {
            const queue = values.reviewStatus?.queue
            if (!queue) {
                actions.removeFromQueueFailure()
                return
            }
            try {
                await llmAnalyticsReviewQueueItemsDestroy(String(ApiConfig.getCurrentProjectId()), queue.itemId)
            } catch {
                lemonToast.error(`Couldn't remove the trace from "${queue.name}". Try again.`)
                actions.removeFromQueueFailure()
                actions.loadReviewStatus()
                return
            }
            lemonToast.success(`Removed from "${queue.name}".`)
            actions.removeFromQueueSuccess()
            actions.loadReviewStatus()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadReviewStatus()
    }),
])
