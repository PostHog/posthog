import { MakeLogicType, afterMount, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiConfig, ApiError } from 'lib/api'
import { urls } from 'scenes/urls'

import { aiObservabilityTracesRetrieve } from '../../generated/api'
import type { TraceApi, TraceNodeApi, TraceTimelineRowApi } from '../../generated/api.schemas'
import { TraceSummaryBarProps } from './components/TraceSummaryBar'
import { encodeTraceIdSegment } from './traceIdSegment'

export interface TraceViewLogicProps {
    traceId: string
    timestampHint: string | null
}

export type TraceViewStatus = 'loading' | 'error' | 'ready'

type LoadFailure = 'not_found' | 'failed'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceViewLogicValues {
    errorMessage: string
    loadFailure: LoadFailure | null
    personLabel: string | null
    status: TraceViewStatus
    summary: TraceSummaryBarProps | null
    timeline: {
        rows: TraceTimelineRowApi[]
        totalMs: number
    }
    trace: TraceApi | null
    traceHasError: boolean
    traceLoading: boolean
    traceName: string
    tree: TraceNodeApi[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceViewLogicActions {
    loadTrace: () => any
    loadTraceFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTraceSuccess: (
        trace: TraceApi,
        payload?: any
    ) => {
        trace: TraceApi
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceViewLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        status: (trace: TraceApi | null, loadFailure: LoadFailure | null) => TraceViewStatus
        errorMessage: (loadFailure: LoadFailure | null) => string
        tree: (trace: TraceApi | null) => TraceNodeApi[]
        timeline: (trace: TraceApi | null) => {
            rows: TraceTimelineRowApi[]
            totalMs: number
        }
        traceName: (trace: TraceApi | null) => string
        traceHasError: (trace: TraceApi | null) => boolean
        personLabel: (trace: TraceApi | null) => string | null
        summary: (trace: TraceApi | null) => TraceSummaryBarProps | null
    }
}

export type traceViewLogicType = MakeLogicType<
    traceViewLogicValues,
    traceViewLogicActions,
    TraceViewLogicProps,
    traceViewLogicMeta
>

export const traceViewLogic = kea<traceViewLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceViewLogic', key]),
    props({} as TraceViewLogicProps),
    key((props) => props.traceId),
    loaders(({ props }) => ({
        trace: [
            null as TraceApi | null,
            {
                loadTrace: async (): Promise<TraceApi> =>
                    await aiObservabilityTracesRetrieve(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        props.timestampHint ? { timestamp_hint: props.timestampHint } : undefined
                    ),
            },
        ],
    })),
    reducers({
        loadFailure: [
            null as LoadFailure | null,
            {
                loadTrace: () => null,
                loadTraceFailure: (_, { errorObject }) =>
                    errorObject instanceof ApiError && errorObject.status === 404 ? 'not_found' : 'failed',
            },
        ],
    }),
    selectors({
        status: [
            (s) => [s.trace, s.loadFailure],
            (trace: TraceApi | null, loadFailure: LoadFailure | null): TraceViewStatus =>
                trace ? 'ready' : loadFailure ? 'error' : 'loading',
        ],
        errorMessage: [
            (s) => [s.loadFailure],
            (loadFailure: LoadFailure | null): string =>
                loadFailure === 'failed'
                    ? 'Something went wrong while loading it. Try again in a moment.'
                    : 'It may have been deleted, or it is outside the retention period.',
        ],
        tree: [(s) => [s.trace], (trace: TraceApi | null): TraceNodeApi[] => trace?.tree ?? []],
        timeline: [
            (s) => [s.trace],
            (trace: TraceApi | null): { rows: TraceTimelineRowApi[]; totalMs: number } => ({
                rows: trace?.timeline ?? [],
                totalMs: trace?.totalMs ?? 0,
            }),
        ],
        traceName: [(s) => [s.trace], (trace: TraceApi | null): string => trace?.name || 'Untitled trace'],
        traceHasError: [(s) => [s.trace], (trace: TraceApi | null): boolean => trace?.hasError ?? false],
        personLabel: [(s) => [s.trace], (trace: TraceApi | null): string | null => trace?.person?.label ?? null],
        summary: [
            (s) => [s.trace],
            (trace: TraceApi | null): TraceSummaryBarProps | null =>
                trace
                    ? {
                          traceId: trace.id,
                          timestamp: trace.createdAt,
                          person: trace.person
                              ? { label: trace.person.label, href: urls.personByDistinctId(trace.person.distinctId) }
                              : null,
                          totals: trace.totals,
                      }
                    : null,
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadTrace()
    }),
])
