function toLoadFailure(error: unknown): LoadFailure {
    return error instanceof ApiError && error.status === 404 ? 'not_found' : 'failed'
}

async function readOrFailure<T>(request: Promise<T>): Promise<{ value: T } | { failure: LoadFailure }> {
    try {
        return { value: await request }
    } catch (error) {
        const failure = toLoadFailure(error)
        if (failure === 'failed' && shouldReportApiFailure(error)) {
            posthog.captureException(error)
        }
        return { failure }
    }
}

// Node ids come from SDKs and URLs, so they can be any string. A plain object keyed by them returns an inherited
// member for an id such as `constructor`, so node state is kept in maps.
function noEntries<V>(): ReadonlyMap<string, V> {
    return new Map()
}

function withEntry<V>(entries: ReadonlyMap<string, V>, nodeId: string, value: V): ReadonlyMap<string, V> {
    return new Map(entries).set(nodeId, value)
}

function withoutEntry<V>(entries: ReadonlyMap<string, V>, nodeId: string): ReadonlyMap<string, V> {
    if (!entries.has(nodeId)) {
        return entries
    }
    const remaining = new Map(entries)
    remaining.delete(nodeId)
    return remaining
}

function firstTimeFor(times: Map<string, number>, nodeId: string): number {
    const time = times.get(nodeId) ?? performance.now()
    times.set(nodeId, time)
    return time
}

function needsRead(current: NodeLoad | undefined, trigger: NodeLoadTrigger): boolean {
    if (!current) {
        return true
    }
    return current.status === 'error' && (trigger === 'selection' || trigger === 'navigation')
}

export function elapsedMs(since: number): number {
    return Math.round(performance.now() - since)
}

export const traceViewLogic = kea<traceViewLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceViewLogic', key]),
    props({} as TraceViewLogicProps),
    key((props) => props.traceId),
    actions({
        loadRawNode: (nodeId: string) => ({ nodeId }),
        rawNodeRequested: (nodeId: string) => ({ nodeId }),
        loadRawNodeSuccess: (nodeId: string, raw: TraceNodeRawApi) => ({ nodeId, raw }),
        loadRawNodeFailure: (nodeId: string, failure: LoadFailure) => ({ nodeId, failure }),
        loadNode: (nodeId: string, trigger: NodeLoadTrigger) => ({ nodeId, trigger }),
        nodeRequested: (nodeId: string, trigger: NodeLoadTrigger) => ({ nodeId, trigger }),
        nodeMissedWithoutHint: (nodeId: string, trigger: NodeLoadTrigger) => ({ nodeId, trigger }),
        loadNodeSuccess: (nodeId: string, node: TraceNodeDetailApi) => ({ nodeId, node }),
        loadNodeFailure: (nodeId: string, failure: LoadFailure) => ({ nodeId, failure }),
    }),
    loaders(({ props, cache }) => ({
        trace: [
            null as TraceApi | null,
            {
                loadTrace: async (): Promise<TraceApi> => {
                    cache.traceRequestedAt = performance.now()
                    return await aiObservabilityTracesRetrieve(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        props.timestampHint ? { timestamp_hint: props.timestampHint } : undefined
                    )
                },
            },
        ],
        evaluationResults: [
            null as TraceEvaluationResultsApi | null,
            {
                loadEvaluationResults: async (): Promise<TraceEvaluationResultsApi> =>
                    await aiObservabilityTracesEvaluationsRetrieve(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId)
                    ),
            },
        ],
    })),
    reducers({
        evaluationResultsFailed: [
            false,
            {
                loadEvaluationResults: () => false,
                loadEvaluationResultsFailure: () => true,
            },
        ],
        loadFailure: [
            null as LoadFailure | null,
            {
                loadTrace: () => null,
                loadTraceFailure: (_, { errorObject }) => toLoadFailure(errorObject),
            },
        ],
        nodes: [
            noEntries<NodeLoad>(),
            {
                nodeRequested: (state, { nodeId }): ReadonlyMap<string, NodeLoad> =>
                    withEntry(state, nodeId, { status: 'loading' }),
                loadNodeSuccess: (state, { nodeId, node }): ReadonlyMap<string, NodeLoad> =>
                    withEntry(state, nodeId, { status: 'ready', node }),
                loadNodeFailure: (state, { nodeId, failure }): ReadonlyMap<string, NodeLoad> =>
                    withEntry(state, nodeId, { status: 'error', failure }),
            },
        ],
        rawNodes: [
            noEntries<RawLoad>(),
            {
                rawNodeRequested: (state, { nodeId }): ReadonlyMap<string, RawLoad> =>
                    withEntry(state, nodeId, { status: 'loading' }),
                loadRawNodeSuccess: (state, { nodeId, raw }): ReadonlyMap<string, RawLoad> =>
                    withEntry(state, nodeId, { status: 'ready', raw }),
                loadRawNodeFailure: (state, { nodeId, failure }): ReadonlyMap<string, RawLoad> =>
                    withEntry(state, nodeId, { status: 'error', failure }),
            },
        ],
    }),
    selectors({
        status: [
            (s) => [s.trace, s.loadFailure],
            (trace: TraceApi | null, loadFailure: LoadFailure | null): TraceViewStatus =>
                trace ? 'ready' : loadFailure ? 'error' : 'loading',
        ],
        tree: [(s) => [s.trace], (trace: TraceApi | null): TraceNodeApi[] => trace?.tree ?? []],
        timeline: [
            (s) => [s.trace],
            (trace: TraceApi | null): { rows: TraceTimelineRowApi[]; totalMs: number } => ({
                rows: trace?.timeline ?? [],
                totalMs: trace?.totalMs ?? 0,
            }),
        ],
        threadNodeIds: [(s) => [s.trace], (trace: TraceApi | null): string[] => trace?.threadNodeIds ?? []],
        createdAt: [(s) => [s.trace], (trace: TraceApi | null): string | null => trace?.createdAt ?? null],
        sessionId: [(s) => [s.trace], (trace: TraceApi | null): string | null => trace?.sessionId ?? null],
        defaultNodeId: [
            (s, p) => [s.trace, p.traceId],
            (trace: TraceApi | null, traceId: string): string => trace?.defaultNodeId ?? traceId,
        ],
        nodeIdsByAlias: [
            (s) => [s.trace],
            (trace: TraceApi | null): ReadonlyMap<string, string> =>
                new Map(Object.entries(trace?.nodeIdsByAlias ?? {})),
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        const selectedAt = (): Map<string, number> => (cache.selectedAt ??= new Map())
        const requestedAt = (): Map<string, number> => (cache.requestedAt ??= new Map())

        const endRead = (nodeId: string): void => {
            selectedAt().delete(nodeId)
            requestedAt().delete(nodeId)
            if (cache.prefetchingNodeId === nodeId) {
                cache.prefetchingNodeId = null
            }
        }

        return {
            loadTraceSuccess: ({ trace }) => {
                // The timeline lists every step but the root.
                traceViewTracking.viewLoaded(elapsedMs(cache.traceRequestedAt), trace.timeline.length + 1)
                for (const nodeId of trace.threadNodeIds) {
                    actions.loadNode(nodeId, 'thread')
                }
            },
            loadNode: ({ nodeId, trigger }) => {
                const current = values.nodes.get(nodeId)
                if (trigger === 'selection' && current?.status !== 'ready') {
                    firstTimeFor(selectedAt(), nodeId)
                }
                if (!needsRead(current, trigger)) {
                    return
                }
                if (trigger === 'prefetch') {
                    // Each read holds one of the organization's query slots, so a slow sweep over the tree must
                    // not start one read per row it crosses.
                    if (cache.prefetchingNodeId) {
                        return
                    }
                    cache.prefetchingNodeId = nodeId
                }
                actions.nodeRequested(nodeId, trigger)
            },
            nodeRequested: async ({ nodeId, trigger }) => {
                const hint = values.createdAt
                const firstRequestedAt = firstTimeFor(requestedAt(), nodeId)
                const result = await readOrFailure(
                    aiObservabilityTracesNodesRetrieve(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        encodeTraceIdSegment(nodeId),
                        hint ? { timestamp_hint: hint } : undefined
                    )
                )
                // A read can answer after the view closed, and a reopened view of the trace shares its actions.
                if (cache.disposables.isDisposed) {
                    return
                }
                if ('failure' in result) {
                    if (result.failure === 'not_found' && !hint) {
                        actions.nodeMissedWithoutHint(nodeId, trigger)
                    } else {
                        actions.loadNodeFailure(nodeId, result.failure)
                    }
                    return
                }
                const waitedSince = selectedAt().get(nodeId)
                const loadMs = elapsedMs(firstRequestedAt)
                const waitedMs = waitedSince === undefined ? null : elapsedMs(waitedSince)
                actions.loadNodeSuccess(nodeId, result.value)
                traceViewTracking.nodeLoaded(trigger, loadMs, waitedMs)
            },
            loadRawNode: ({ nodeId }) => {
                const status = values.rawNodes.get(nodeId)?.status
                if (status !== 'loading' && status !== 'ready') {
                    actions.rawNodeRequested(nodeId)
                }
            },
            rawNodeRequested: async ({ nodeId }) => {
                const hint = values.createdAt
                const result = await readOrFailure(
                    aiObservabilityTracesNodesRawRetrieve(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        encodeTraceIdSegment(nodeId),
                        hint ? { timestamp_hint: hint } : undefined
                    )
                )
                if (cache.disposables.isDisposed) {
                    return
                }
                if ('failure' in result) {
                    actions.loadRawNodeFailure(nodeId, result.failure)
                } else {
                    actions.loadRawNodeSuccess(nodeId, result.value)
                }
            },
            loadNodeSuccess: ({ nodeId }) => endRead(nodeId),
            loadNodeFailure: ({ nodeId }) => endRead(nodeId),
        }
    }),
    afterMount(({ actions }) => {
        actions.loadTrace()
        actions.loadEvaluationResults()
    }),
    // Without a hint the backend reads ai_events only, so an early read of a node from a trace past the ai_events
    // retention misses. The node stays loading and is read again once the trace's timestamp is known.
    reducers({
        nodesMissedWithoutHint: [
            noEntries<NodeLoadTrigger>(),
            {
                nodeMissedWithoutHint: (state, { nodeId, trigger }): ReadonlyMap<string, NodeLoadTrigger> =>
                    withEntry(state, nodeId, trigger),
                nodeRequested: (state, { nodeId }): ReadonlyMap<string, NodeLoadTrigger> => withoutEntry(state, nodeId),
                loadNodeFailure: (state, { nodeId }): ReadonlyMap<string, NodeLoadTrigger> =>
                    withoutEntry(state, nodeId),
            },
        ],
    }),
    listeners(({ actions, values }) => {
        // The timeline lists every tree node, so an id outside it is a stale or SDK id that no hint will find.
        const isTraceNode = (trace: TraceApi, nodeId: string): boolean =>
            nodeId === trace.id || trace.timeline.some((row) => row.id === nodeId)

        const rereadMissedNodes = (): void => {
            const { trace } = values
            if (!trace) {
                return
            }
            for (const [nodeId, trigger] of values.nodesMissedWithoutHint) {
                if (isTraceNode(trace, nodeId)) {
                    actions.nodeRequested(nodeId, trigger)
                } else {
                    actions.loadNodeFailure(nodeId, 'not_found')
                }
            }
        }

        return {
            loadTraceSuccess: rereadMissedNodes,
            nodeMissedWithoutHint: rereadMissedNodes,
        }
    }),
])
