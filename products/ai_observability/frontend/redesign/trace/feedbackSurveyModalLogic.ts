/** Creates a thumbs up/down feedback survey from a trace's Feedback tab. */
export const feedbackSurveyModalLogic = kea<feedbackSurveyModalLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'feedbackSurveyModalLogic']),
    actions({
        openModal: true,
        closeModal: true,
        setCreatedSurvey: (survey: Survey | null) => ({ survey }),
    }),
    reducers({
        isOpen: [
            false,
            {
                openModal: () => true,
                closeModal: () => false,
            },
        ],
        createdSurvey: [
            null as Survey | null,
            {
                setCreatedSurvey: (_, { survey }) => survey,
                openModal: () => null,
            },
        ],
    }),
    forms(({ actions }) => ({
        feedbackSurvey: {
            defaults: DEFAULT_FORM_VALUES,
            errors: ({ name, followUpEnabled, followUpQuestion }) => ({
                name: !name?.trim() ? 'Please enter a survey name' : undefined,
                followUpQuestion:
                    followUpEnabled && !followUpQuestion?.trim() ? 'Please enter a follow-up question' : undefined,
            }),
            submit: async (formValues) => {
                try {
                    const survey = await api.surveys.create(buildFeedbackSurveyPayload(formValues))
                    actions.setCreatedSurvey(survey)
                    lemonToast.success('Feedback survey created')
                    void addProductIntent({
                        product_type: ProductKey.SURVEYS,
                        intent_context: ProductIntentContext.SURVEY_CREATED,
                        metadata: {
                            survey_id: survey.id,
                            source: SURVEY_CREATED_SOURCE.LLM_ANALYTICS,
                            created_successfully: true,
                        },
                    })
                } catch (error: any) {
                    lemonToast.error(error?.detail || 'Failed to create the feedback survey')
                }
            },
        },
    })),
    listeners(({ actions }) => ({
        openModal: () => {
            actions.resetFeedbackSurvey(DEFAULT_FORM_VALUES)
        },
    })),
])
