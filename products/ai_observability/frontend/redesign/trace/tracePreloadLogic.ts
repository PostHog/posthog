import { MakeLogicType, actions, kea, listeners, path, reducers } from 'kea'

import { ApiConfig } from 'lib/api'
import { objectsEqual } from 'lib/utils/objects'

import type { TraceApi, TraceNodeDetailApi } from '../../generated/api.schemas'
import { noEntries } from '../shared/readOrFailure'
import { TraceListRow, uniqueTraces } from './traceListRows'
import { readTrace, readTraceNode } from './traceReads'
import type { TraceOverview, TraceSeed } from './types'

// A pointer sweeping across the list must not start a read for every row it crosses.
export const ROW_PREFETCH_DWELL_MS = 150
export const PREFETCH_MAX_AGE_MS = 30_000
const ROW_PREFETCH_DWELL_DISPOSABLE = 'rowPrefetchDwell'

/**
 * Which trace and step were prefetched, and the row overview they were prefetched for. Their reads are promises, so
 * they live in the logic's cache, not in state.
 */
export interface PrefetchedTrace {
    traceId: string
    nodeId: string
    overview: TraceOverview
}

interface PrefetchedReads {
    trace: Promise<TraceApi>
    node: Promise<TraceNodeDetailApi>
    startedAt: number
}

/** The reads of a trace and its default step, started before the row was opened, so opening awaits them. */
export type FreshPrefetch = PrefetchedTrace & Omit<PrefetchedReads, 'startedAt'>

function freshReads(
    prefetched: PrefetchedTrace | null,
    reads: PrefetchedReads | null,
    traceId: string,
    now: number
): FreshPrefetch | null {
    if (prefetched?.traceId !== traceId || !reads || now - reads.startedAt > PREFETCH_MAX_AGE_MS) {
        return null
    }
    return { ...prefetched, trace: reads.trace, node: reads.node }
}

/** The prefetched reads of a trace, or null when another trace was prefetched or its reads are too old to trust. */
export function freshPrefetch(traceId: string): FreshPrefetch | null {
    const logic = tracePreloadLogic.findMounted()
    if (!logic) {
        return null
    }
    const reads: PrefetchedReads | null = logic.cache.prefetchedReads ?? null
    return freshReads(logic.values.prefetched, reads, traceId, Date.now())
}

// A row's overview is the whole list item, so this keeps only the overview's own fields for comparing.
function overviewFacts({
    id,
    name,
    createdAt,
    sessionId,
    totals,
    hasError,
    errorCount,
    totalsPartial,
}: TraceOverview): TraceOverview {
    return { id, name, createdAt, sessionId, totals, hasError, errorCount, totalsPartial }
}

// A reload can list the trace again with newer facts, and opening it on an older prefetched read would paint the
// newer header and then replace it with older totals or errors.
function stillListed(prefetched: PrefetchedTrace | null, rows: TraceListRow[]): PrefetchedTrace | null {
    if (!prefetched) {
        return null
    }
    const row = uniqueTraces(rows).find(({ traceId }) => traceId === prefetched.traceId)
    const unchanged =
        !!row?.overview &&
        row.defaultStepId === prefetched.nodeId &&
        objectsEqual(overviewFacts(row.overview), prefetched.overview)
    return unchanged ? prefetched : null
}

function toSeeds(rows: TraceListRow[]): ReadonlyMap<string, TraceSeed> {
    const seeds = new Map<string, TraceSeed>()
    for (const { traceId, overview, defaultStepId, person } of uniqueTraces(rows)) {
        if (overview) {
            seeds.set(traceId, { overview, defaultStepId: defaultStepId ?? null, person })
        }
    }
    return seeds
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracePreloadLogicValues {
    prefetchInFlight: boolean
    prefetched: PrefetchedTrace | null
    seeds: ReadonlyMap<string, TraceSeed>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracePreloadLogicActions {
    prefetchSettled: () => {
        value: true
    }
    prefetchTrace: (traceId: string) => {
        traceId: string
    }
    releasePrefetched: (traceId: string) => {
        traceId: string
    }
    rowEntered: (traceId: string) => {
        traceId: string
    }
    rowLeft: () => {
        value: true
    }
    seedRows: (rows: TraceListRow[]) => {
        rows: TraceListRow[]
    }
    tracePrefetched: (
        traceId: string,
        nodeId: string,
        overview: TraceOverview
    ) => {
        nodeId: string
        overview: TraceOverview
        traceId: string
    }
}

export type tracePreloadLogicType = MakeLogicType<tracePreloadLogicValues, tracePreloadLogicActions>

export const tracePreloadLogic = kea<tracePreloadLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'tracePreloadLogic']),
    actions({
        seedRows: (rows: TraceListRow[]) => ({ rows }),
        rowEntered: (traceId: string) => ({ traceId }),
        rowLeft: true,
        prefetchTrace: (traceId: string) => ({ traceId }),
        tracePrefetched: (traceId: string, nodeId: string, overview: TraceOverview) => ({
            traceId,
            nodeId,
            overview: overviewFacts(overview),
        }),
        prefetchSettled: true,
        releasePrefetched: (traceId: string) => ({ traceId }),
    }),
    reducers({
        seeds: [
            noEntries<TraceSeed>(),
            {
                seedRows: (_, { rows }) => toSeeds(rows),
            },
        ],
        prefetched: [
            null as PrefetchedTrace | null,
            {
                tracePrefetched: (_, { traceId, nodeId, overview }) => ({ traceId, nodeId, overview }),
                releasePrefetched: (prefetched, { traceId }) => (prefetched?.traceId === traceId ? null : prefetched),
                seedRows: (prefetched, { rows }) => stillListed(prefetched, rows),
            },
        ],
        // At most one prefetch is in flight, because each read holds one of the organization's query slots.
        prefetchInFlight: [
            false,
            {
                tracePrefetched: () => true,
                prefetchSettled: () => false,
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const dropReleasedReads = (): void => {
            if (!values.prefetched) {
                cache.prefetchedReads = null
            }
        }

        return {
            rowEntered: ({ traceId }) => {
                cache.disposables.add(() => {
                    const timer = setTimeout(() => actions.prefetchTrace(traceId), ROW_PREFETCH_DWELL_MS)
                    return () => clearTimeout(timer)
                }, ROW_PREFETCH_DWELL_DISPOSABLE)
            },
            rowLeft: () => {
                cache.disposables.dispose(ROW_PREFETCH_DWELL_DISPOSABLE)
            },
            prefetchTrace: ({ traceId }) => {
                const seed = values.seeds.get(traceId)
                const startedAt = Date.now()
                if (
                    !seed?.defaultStepId ||
                    values.prefetchInFlight ||
                    freshReads(values.prefetched, cache.prefetchedReads ?? null, traceId, startedAt)
                ) {
                    return
                }
                const projectId = String(ApiConfig.getCurrentProjectId())
                const hint = seed.overview.createdAt
                const reads: PrefetchedReads = {
                    trace: readTrace(projectId, traceId, hint),
                    node: readTraceNode(projectId, traceId, seed.defaultStepId, hint),
                    startedAt,
                }
                cache.prefetchedReads = reads
                actions.tracePrefetched(traceId, seed.defaultStepId, seed.overview)
                // Captured now, because a later mount puts a live manager on the cache that this read must not dispatch to.
                const disposables = cache.disposables
                // allSettled also handles both rejections, so a failed prefetch never surfaces. The view reads again.
                void Promise.allSettled([reads.trace, reads.node]).then(() => {
                    if (!disposables.isDisposed) {
                        actions.prefetchSettled()
                    }
                })
            },
            releasePrefetched: dropReleasedReads,
            seedRows: dropReleasedReads,
        }
    }),
])
