const EXCEPTION_LOOKUP_WINDOW_MINUTES = 20

const LAYOUT_NAV_OVERRIDE_OWNER = 'ai-trace-page'

function searchParamFromUrl(): string {
    return rawSearchParam(router.values.location.search, 'search') ?? ''
}

function replaceUrlParams(changes: Record<string, string | undefined>): void {
    router.actions.replace(
        router.values.location.pathname,
        { ...router.values.searchParams, search: searchParamFromUrl() || undefined, ...changes },
        router.values.hashParams
    )
}

// An unencoded `+` in a URL query decodes to a space, so `+00:00` arrives as ` 00:00`.
function parseUrlDate(value: string): string | null {
    const raw = String(value).trim()
    if (dayjs(raw).isValid()) {
        return raw
    }
    const repaired = raw.replace(/ (\d{2}:?\d{2})$/, '+$1')
    return dayjs(repaired).isValid() ? repaired : null
}

