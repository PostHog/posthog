function toTimestampHint(timestamp?: string, exceptionTimestamp?: string): string | null {
    const dateFrom = timestamp ? parseUrlDate(timestamp) : null
    if (dateFrom) {
        return dateFrom
    }
    const exceptionDate = exceptionTimestamp ? parseUrlDate(exceptionTimestamp) : null
    return exceptionDate
        ? dayjs(exceptionDate).subtract(EXCEPTION_LOOKUP_WINDOW_MINUTES, 'minutes').toISOString()
        : null
}

export const tracePageLogic = kea<tracePageLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'tracePageLogic']),
    connect(() => ({
        actions: [
            traceViewHostLogic({ hostId: TRACE_PAGE_HOST_ID }),
            ['setMode', 'setDetailTab', 'requestStep', 'publishQuery', 'setOpeningMode', 'setSeedQuery'],
            panelLayoutLogic,
            ['setLayoutNavCollapsedOverride'],
        ],
    })),
    actions({
        setTraceId: (traceId: string) => ({ traceId }),
        setTimestampHint: (timestampHint: string | null) => ({ timestampHint }),
    }),
    reducers({
        traceId: [
            '',
            {
                setTraceId: (_, { traceId }) => traceId,
            },
        ],
        timestampHint: [
            null as string | null,
            {
                setTimestampHint: (_, { timestampHint }) => timestampHint,
            },
        ],
    }),
    selectors({
        backLink: [
            () => [router.selectors.searchParams],
            (searchParams: Record<string, unknown>): LabeledLink => toBackLink(searchParams),
        ],
    }),
    listeners(() => ({
        requestStep: ({ stepId }) => {
            if ((router.values.searchParams.event ?? null) !== stepId) {
                replaceUrlParams({ event: stepId ?? undefined })
            }
        },
        publishQuery: ({ query }) => {
            if (searchParamFromUrl() !== query) {
                replaceUrlParams({ search: query || undefined })
            }
        },
    })),
    urlToAction(({ actions, values }) => ({
        [`${urls.aiObservabilityTraces()}/:id`]: ({ id }, { event, timestamp, exception_ts, tab }) => {
            const traceId = tryDecodeURIComponent(id ?? '')
            const isNewTrace = traceId !== values.traceId
            // The page opens each trace from the start. Only a host that steps through traces carries these over.
            if (isNewTrace && values.traceId) {
                actions.setMode('spans')
                actions.setDetailTab('messages')
            }
            // The page writes its URL on each step, so a later pass here would undo the tab the person picked.
            if (isNewTrace && tab === 'evals') {
                actions.setDetailTab('evals')
            }
            actions.setTraceId(traceId)
            // An eval link with no event comes from a trace-level run, and only the root shows that run.
            actions.requestStep(event || (tab === 'evals' ? traceId : null), traceId)
            actions.setOpeningMode(tab === 'summary' ? 'summary' : null)
            actions.setSeedQuery(searchParamFromUrl())
            const timestampHint = toTimestampHint(timestamp, exception_ts)
            if (timestampHint || isNewTrace) {
                actions.setTimestampHint(timestampHint)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.setLayoutNavCollapsedOverride(LAYOUT_NAV_OVERRIDE_OWNER, true)
    }),
    beforeUnmount(({ actions }) => {
        actions.setLayoutNavCollapsedOverride(LAYOUT_NAV_OVERRIDE_OWNER, null)
    }),
])
