export const traceViewAdapterLogic = kea<traceViewAdapterLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceViewAdapterLogic', key]),
    props({} as TraceViewAdapterLogicProps),
    key((props) => props.traceId),
    connect((props: TraceViewAdapterLogicProps) => ({
        values: [
            traceViewLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['status', 'errorMessage', 'tree', 'summary', 'timeline', 'traceName', 'traceHasError', 'personLabel'],
            aiObservabilityTraceLogic,
            ['olderTraceId', 'olderTimestamp', 'newerTraceId', 'newerTimestamp'],
            aiObservabilityTraceDataLogic({
                traceId: props.traceId,
                query: props.query,
                cachedResults: null,
                searchQuery: '',
            }),
            ['trace', 'event'],
            aiObservabilityAIDataLogic,
            ['aiDataCache'],
            generationEvaluationRunsLogic({ traceId: props.traceId }),
            ['generationEvaluationRuns', 'generationEvaluationRunsLoading'],
            teamLogic,
            ['currentTeamId'],
            llmEvaluationsLogic,
            ['evaluations', 'detectorEvaluationIds', 'evaluationsSettled'],
            router,
            ['searchParams'],
        ],
        actions: [aiObservabilityTraceLogic, ['setEventId'], aiObservabilityAIDataLogic, ['ensureAIDataLoaded']],
    })),
    actions({
        setMode: (mode: TraceMode) => ({ mode }),
        setDetailTab: (tab: NodeDetailTab) => ({ tab }),
        selectNode: (id: string) => ({ id }),
        selectAndShowSpans: (id: string) => ({ id }),
        viewInThread: true,
    }),
    reducers({
        mode: [
            'spans' as TraceMode,
            {
                setMode: (_, { mode }) => mode,
                selectAndShowSpans: () => 'spans',
                viewInThread: () => 'thread',
            },
        ],
        detailTab: ['messages' as NodeDetailTab, { setDetailTab: (_, { tab }) => tab }],
    }),
    selectors({
        selectedNodeId: [
            (s, p) => [s.event, p.traceId],
            (event: LLMTrace | LLMTraceEvent | null, traceId: string): string | null =>
                event ? (isLLMEvent(event) ? event.id : traceId) : null,
        ],
        selectedTreeNode: [
            (s) => [s.tree, s.selectedNodeId],
            (tree: TraceNodeApi[], selectedNodeId: string | null): TraceNodeApi | null =>
                selectedNodeId ? findTreeNode(tree, selectedNodeId) : null,
        ],
        backLink: [
            (s) => [s.searchParams],
            (searchParams: Record<string, unknown>): LabeledLink => toBackLink(searchParams),
        ],
        header: [
            (s) => [
                s.traceName,
                s.traceHasError,
                s.olderTraceId,
                s.olderTimestamp,
                s.newerTraceId,
                s.newerTimestamp,
                s.searchParams,
            ],
            (
                traceName: string,
                traceHasError: boolean,
                olderTraceId: string | null,
                olderTimestamp: string | null,
                newerTraceId: string | null,
                newerTimestamp: string | null,
                searchParams: Record<string, unknown>
            ): TraceHeaderProps =>
                toHeader(
                    { name: traceName, hasError: traceHasError },
                    { olderTraceId, olderTimestamp, newerTraceId, newerTimestamp },
                    searchParams
                ),
        ],
        detailData: [
            (s) => [
                s.trace,
                s.event,
                s.tree,
                s.selectedTreeNode,
                s.aiDataCache,
                s.generationEvaluationRuns,
                s.generationEvaluationRunsLoading,
                s.evaluations,
                s.detectorEvaluationIds,
                s.evaluationsSettled,
                s.currentTeamId,
                s.personLabel,
            ],
            (
                trace: LLMTrace | undefined,
                event: LLMTrace | LLMTraceEvent | null,
                tree: TraceNodeApi[],
                node: TraceNodeApi | null,
                cache: Record<string, AIData | null>,
                evalRuns: EvaluationRun[],
                evalRunsLoading: boolean,
                evaluations: EvaluationConfig[],
                detectorEvaluationIds: string[],
                evaluationsSettled: boolean,
                teamId: number | null,
                person: string | null
            ): NodeDetailData | null =>
                trace && event && node
                    ? toNodeDetail({
                          trace,
                          event,
                          tree,
                          node,
                          cache,
                          evalRuns,
                          evalRunsLoading,
                          evaluations,
                          detectorEvaluationIds,
                          evaluationsSettled,
                          teamId,
                          person,
                      })
                    : null,
        ],
        thread: [
            (s) => [s.trace, s.aiDataCache, s.currentTeamId],
            (
                trace: LLMTrace | undefined,
                cache: Record<string, AIData | null>,
                teamId: number | null
            ): ConversationState => (trace ? toThread(trace, cache, teamId) : { status: 'loading' }),
        ],
        canViewInThread: [
            (s, p) => [s.selectedNodeId, s.thread, p.traceId],
            (selectedNodeId: string | null, thread: ConversationState, traceId: string): boolean => {
                if (!selectedNodeId) {
                    return false
                }
                if (selectedNodeId === traceId) {
                    return true
                }
                const turnMessages = thread.status === 'ready' ? (thread.turns[0]?.messages ?? []) : []
                return turnMessages.some((message) => message.sourceNodeId === selectedNodeId)
            },
        ],
        heavyDataLookups: [
            (s) => [s.trace, s.event],
            (trace: LLMTrace | undefined, event: LLMTrace | LLMTraceEvent | null): AIDataLookup[] => {
                if (!trace) {
                    return []
                }
                const candidates = [event && isLLMEvent(event) ? event : null, pickUserVisibleTurn(trace) ?? null]
                return candidates
                    .map((candidate) => (candidate ? heavyDataLookup(candidate, trace.id) : null))
                    .filter((lookup): lookup is AIDataLookup => lookup !== null)
            },
        ],
    }),
    listeners(({ actions }) => ({
        selectNode: ({ id }) => actions.setEventId(id),
        selectAndShowSpans: ({ id }) => actions.setEventId(id),
    })),
    subscriptions(({ actions }) => ({
        heavyDataLookups: (lookups: AIDataLookup[]) => {
            if (lookups.length > 0) {
                actions.ensureAIDataLoaded(lookups)
            }
        },
    })),
    afterMount(() => {
        // The legacy scene writes a `search` param into shared trace links. This view has no
        // search UI, so without clearing it the tree silently filters down to whatever the
        // stale query matched. Removing only that param keeps every other permalink param, and
        // the legacy trace logic reads the new URL and clears its search query.
        const { search, ...searchParams } = router.values.searchParams
        if (search !== undefined) {
            router.actions.replace(router.values.location.pathname, searchParams, router.values.hashParams)
        }
    }),
])
