const LOADING: NodeLoad = { status: 'loading' }
// Skimming the tree with the pointer must not start a read for every row it crosses.
const PREFETCH_DELAY_MS = 75

export const traceViewAdapterLogic = kea<traceViewAdapterLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceViewAdapterLogic', key]),
    props({} as TraceViewAdapterLogicProps),
    key((props) => props.traceId),
    connect((props: TraceViewAdapterLogicProps) => ({
        values: [
            traceViewLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            [
                'status',
                'errorMessage',
                'tree',
                'summary',
                'timeline',
                'traceName',
                'traceHasError',
                'personLabel',
                'nodes',
                'threadNodeIds',
                'createdAt',
                'sessionId',
                'defaultNodeId',
                'nodeIdsByAlias',
                'evaluationResults',
                'evaluationResultsFailed',
                'trace',
            ],
            aiObservabilityTraceLogic,
            ['eventId', 'initialTab', 'olderTraceId', 'olderTimestamp', 'newerTraceId', 'newerTimestamp'],
            teamLogic,
            ['currentTeamId'],
            router,
            ['searchParams'],
            featureFlagLogic,
            ['featureFlags'],
            traceClustersLogic({ traceId: props.traceId }),
            ['clusters'],
            traceSummaryLogic({ traceId: props.traceId }),
            ['state as summaryState', 'requesting as summaryRequesting', 'requestError as summaryRequestError'],
            aiConsentLogic,
            ['dataProcessingAccepted as summaryConsentGiven'],
        ],
        actions: [
            aiObservabilityTraceLogic,
            ['setEventId', 'loadNeighbors'],
            traceViewLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['loadNode', 'loadTraceSuccess'],
            traceClustersLogic({ traceId: props.traceId }),
            ['loadClusters'],
            traceSummaryLogic({ traceId: props.traceId }),
            ['openSummary', 'closeSummary', 'requestSummary', 'loadSummary'],
        ],
    })),
    actions({
        setMode: (mode: TraceMode) => ({ mode }),
        setDetailTab: (tab: NodeDetailTab) => ({ tab }),
        selectNode: (id: string) => ({ id }),
        selectAndShowSpans: (id: string) => ({ id }),
        viewInThread: true,
        prefetchNode: (id: string) => ({ id }),
        showFailingEvals: true,
        openSummaryFromLink: true,
        summarize: true,
        regenerateSummary: true,
        summaryStepClicked: (nodeId: string, kind: SummaryItemKind) => ({ nodeId, kind }),
    }),
    reducers({
        mode: [
            'spans' as TraceMode,
            {
                setMode: (_, { mode }) => mode,
                selectAndShowSpans: () => 'spans',
                viewInThread: () => 'thread',
                openSummaryFromLink: () => 'summary',
            },
        ],
        detailTab: ['messages' as NodeDetailTab, { setDetailTab: (_, { tab }) => tab }],
    }),
    selectors({
        selectedNodeId: [
            (s, p) => [s.eventId, s.initialTab, s.tree, s.status, s.defaultNodeId, s.nodeIdsByAlias, p.traceId],
            (
                eventId: string | null,
                initialTab: string | null,
                tree: TraceNodeApi[],
                status: TraceViewStatus,
                defaultNodeId: string,
                nodeIdsByAlias: Record<string, string>,
                traceId: string
            ): string => {
                if (status !== 'ready') {
                    return eventId ?? traceId
                }
                if (!eventId) {
                    // Trace-level links from clusters and sessions ask for the trace itself with tab=summary.
                    return initialTab === 'summary' ? traceId : defaultNodeId
                }
                if (findTreeNode(tree, eventId)) {
                    return eventId
                }
                return nodeIdsByAlias[eventId] ?? traceId
            },
        ],
        selectedTreeNode: [
            (s) => [s.tree, s.selectedNodeId],
            (tree: TraceNodeApi[], selectedNodeId: string): TraceNodeApi | null => findTreeNode(tree, selectedNodeId),
        ],
        // Each consumer reads its own node load, so a prefetch of another node does not rebuild its heavy messages.
        selectedNodeLoad: [
            (s) => [s.selectedNodeId, s.nodes],
            (selectedNodeId: string, nodes: Record<string, NodeLoad>): NodeLoad => nodes[selectedNodeId] ?? LOADING,
        ],
        threadNodeLoad: [
            (s) => [s.threadNodeIds, s.nodes],
            (threadNodeIds: string[], nodes: Record<string, NodeLoad>): NodeLoad | null =>
                threadNodeIds[0] ? (nodes[threadNodeIds[0]] ?? LOADING) : null,
        ],
        backLink: [
            (s) => [s.searchParams],
            (searchParams: Record<string, unknown>): LabeledLink => toBackLink(searchParams),
        ],
        header: [
            (s) => [
                s.traceName,
                s.traceHasError,
                s.olderTraceId,
                s.olderTimestamp,
                s.newerTraceId,
                s.newerTimestamp,
                s.searchParams,
            ],
            (
                traceName: string,
                traceHasError: boolean,
                olderTraceId: string | null,
                olderTimestamp: string | null,
                newerTraceId: string | null,
                newerTimestamp: string | null,
                searchParams: Record<string, unknown>
            ): TraceHeaderProps =>
                toHeader(
                    { name: traceName, hasError: traceHasError },
                    { olderTraceId, olderTimestamp, newerTraceId, newerTimestamp },
                    searchParams
                ),
        ],
        detailData: [
            (s) => [
                s.selectedTreeNode,
                s.selectedNodeLoad,
                s.tree,
                s.evaluationResults,
                s.evaluationResultsFailed,
                s.currentTeamId,
                s.personLabel,
                s.createdAt,
                s.sessionId,
            ],
            (
                node: TraceNodeApi | null,
                load: NodeLoad,
                tree: TraceNodeApi[],
                evaluationResults: TraceEvaluationResultsApi | null,
                evaluationResultsFailed: boolean,
                teamId: number | null,
                person: string | null,
                createdAt: string | null,
                sessionId: string | null
            ): NodeDetailData | null =>
                node && createdAt
                    ? toNodeDetail({
                          node,
                          load,
                          tree,
                          evaluationResults: evaluationResults?.results ?? null,
                          evaluationResultsFailed,
                          teamId,
                          person,
                          trace: { createdAt, sessionId },
                      })
                    : null,
        ],
        datasetItemSource: [
            (s, p) => [s.featureFlags, s.selectedNodeLoad, s.createdAt, p.traceId],
            (
                featureFlags: FeatureFlagsSet,
                load: NodeLoad,
                createdAt: string | null,
                traceId: string
            ): SaveToDatasetButtonProps | null =>
                featureFlags[FEATURE_FLAGS.LLM_ANALYTICS_DATASETS] && createdAt
                    ? toDatasetItemSource({ traceId, createdAt, load })
                    : null,
        ],
        thread: [
            (s, p) => [s.status, s.threadNodeLoad, s.createdAt, s.currentTeamId, p.traceId],
            (
                status: TraceViewStatus,
                load: NodeLoad | null,
                createdAt: string | null,
                teamId: number | null,
                traceId: string
            ): ConversationState => {
                if (status !== 'ready' || !createdAt) {
                    return { status: 'loading' }
                }
                return toThread({ traceId, createdAt, load, teamId })
            },
        ],
        clustersChip: [
            (s) => [s.clusters],
            (clusters: TraceClusterApi[] | null): TraceClustersChipProps | null => toClustersChip(clusters),
        ],
        evalsChip: [
            (s) => [s.evaluationResults],
            (evaluationResults: TraceEvaluationResultsApi | null): EvalsChipData | null =>
                evaluationResults ? toEvalsChip(evaluationResults.summary) : null,
        ],
        evalOutcomesByNode: [
            (s) => [s.evaluationResults],
            (evaluationResults: TraceEvaluationResultsApi | null): Record<string, EvalRollupOutcome> =>
                evaluationResults ? toEvalOutcomesByNode(evaluationResults.summary) : {},
        ],
        gitBranch: [(s) => [s.trace], (trace: TraceApi | null): GitBranchChipProps | null => trace?.git ?? null],
        canViewInThread: [
            (s, p) => [s.selectedNodeId, s.threadNodeIds, p.traceId],
            (selectedNodeId: string, threadNodeIds: string[], traceId: string): boolean =>
                selectedNodeId === traceId || threadNodeIds.includes(selectedNodeId),
        ],
    }),
    listeners(({ actions, values, selectors, props }) => {
        // The click's read starts before the selection moves, so the selectedNodeId subscription's navigation read
        // for the same id is deduped and the load event reports a click. Selecting the node that is already
        // selected changes no value and the subscription does not fire, so this read also retries a failed node.
        const select = ({ id }: { id: string }): void => {
            actions.loadNode(id, 'selection')
            actions.setEventId(id)
        }
        const syncSummary = (previousMode: TraceMode): void => {
            const wasOpen = previousMode === 'summary'
            if (values.mode === 'summary' && !wasOpen) {
                actions.openSummary('tab')
            } else if (values.mode !== 'summary' && wasOpen) {
                actions.closeSummary()
            }
        }
        const requestSummary = (regenerate: boolean): void => {
            actions.requestSummary({ regenerate, timestampHint: values.createdAt })
        }
        return {
            setMode: (_, __, ___, previousState) => syncSummary(selectors.mode(previousState)),
            viewInThread: (_, __, ___, previousState) => syncSummary(selectors.mode(previousState)),
            selectNode: select,
            selectAndShowSpans: (payload, __, ___, previousState) => {
                select(payload)
                syncSummary(selectors.mode(previousState))
            },
            prefetchNode: async ({ id }, breakpoint) => {
                await breakpoint(PREFETCH_DELAY_MS)
                actions.loadNode(id, 'prefetch')
            },
            loadTraceSuccess: ({ trace }) => {
                actions.loadNeighbors(props.traceId, trace.createdAt)
                actions.loadClusters(trace.createdAt)
                // Cluster and session pages link to a trace with tab=summary. The mode opens without generating.
                // A link that also names a step opens that step, because the Summary mode covers the whole trace.
                if (values.initialTab === 'summary' && values.mode !== 'summary' && !values.eventId) {
                    actions.openSummaryFromLink()
                }
            },
            openSummaryFromLink: () => actions.openSummary('link'),
            summarize: () => requestSummary(false),
            regenerateSummary: () => requestSummary(true),
            summaryStepClicked: ({ nodeId, kind }) => {
                posthog.capture('llma trace view summary step clicked', { kind })
                actions.selectAndShowSpans(nodeId)
            },
            showFailingEvals: () => {
                actions.selectAndShowSpans(firstFailingNodeId(values.tree, values.evalOutcomesByNode) ?? props.traceId)
                actions.setDetailTab('evals')
            },
        }
    }),
    subscriptions(({ actions }) => ({
        selectedNodeId: (selectedNodeId: string) => actions.loadNode(selectedNodeId, 'navigation'),
    })),
])
