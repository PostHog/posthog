const LOADING: NodeLoad = { status: 'loading' }
// Skimming the tree with the pointer must not start a read for every row it crosses.
const PREFETCH_DELAY_MS = 75

export const traceViewAdapterLogic = kea<traceViewAdapterLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceViewAdapterLogic', key]),
    props({} as TraceViewAdapterLogicProps),
    key((props) => props.traceId),
    connect((props: TraceViewAdapterLogicProps) => ({
        values: [
            traceViewLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            [
                'status',
                'errorMessage',
                'tree',
                'summary',
                'timeline',
                'traceName',
                'traceHasError',
                'personLabel',
                'nodes',
                'threadNodeIds',
                'createdAt',
                'sessionId',
                'defaultNodeId',
                'nodeIdsByAlias',
                'evaluationResults',
                'evaluationResultsFailed',
            ],
            aiObservabilityTraceLogic,
            ['eventId', 'initialTab', 'olderTraceId', 'olderTimestamp', 'newerTraceId', 'newerTimestamp'],
            teamLogic,
            ['currentTeamId'],
            router,
            ['searchParams'],
            featureFlagLogic,
            ['featureFlags'],
            traceSearchLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['query', 'searchResults', 'searchStatus', 'searchFailure'],
        ],
        actions: [
            aiObservabilityTraceLogic,
            ['setEventId', 'loadNeighbors'],
            traceViewLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['loadNode', 'loadTraceSuccess'],
            traceSearchLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['setQuery'],
        ],
    })),
    actions({
        setMode: (mode: TraceMode) => ({ mode }),
        setDetailTab: (tab: NodeDetailTab) => ({ tab }),
        selectNode: (id: string) => ({ id }),
        selectAndShowSpans: (id: string) => ({ id }),
        viewInThread: true,
        prefetchNode: (id: string) => ({ id }),
        stepMatch: (direction: MatchDirection) => ({ direction }),
    }),
    reducers({
        mode: [
            'spans' as TraceMode,
            {
                setMode: (_, { mode }) => mode,
                selectAndShowSpans: () => 'spans',
                viewInThread: () => 'thread',
            },
        ],
        detailTab: ['messages' as NodeDetailTab, { setDetailTab: (_, { tab }) => tab }],
    }),
    selectors({
        selectedNodeId: [
            (s, p) => [s.eventId, s.initialTab, s.tree, s.status, s.defaultNodeId, s.nodeIdsByAlias, p.traceId],
            (
                eventId: string | null,
                initialTab: string | null,
                tree: TraceNodeApi[],
                status: TraceViewStatus,
                defaultNodeId: string,
                nodeIdsByAlias: Record<string, string>,
                traceId: string
            ): string => {
                if (status !== 'ready') {
                    return eventId ?? traceId
                }
                if (!eventId) {
                    // Trace-level links from clusters and sessions ask for the trace itself with tab=summary.
                    return initialTab === 'summary' ? traceId : defaultNodeId
                }
                if (findTreeNode(tree, eventId)) {
                    return eventId
                }
                return nodeIdsByAlias[eventId] ?? traceId
            },
        ],
        selectedTreeNode: [
            (s) => [s.tree, s.selectedNodeId],
            (tree: TraceNodeApi[], selectedNodeId: string): TraceNodeApi | null => findTreeNode(tree, selectedNodeId),
        ],
        // Each consumer reads its own node load, so a prefetch of another node does not rebuild its heavy messages.
        selectedNodeLoad: [
            (s) => [s.selectedNodeId, s.nodes],
            (selectedNodeId: string, nodes: Record<string, NodeLoad>): NodeLoad => nodes[selectedNodeId] ?? LOADING,
        ],
        threadNodeLoad: [
            (s) => [s.threadNodeIds, s.nodes],
            (threadNodeIds: string[], nodes: Record<string, NodeLoad>): NodeLoad | null =>
                threadNodeIds[0] ? (nodes[threadNodeIds[0]] ?? LOADING) : null,
        ],
        backLink: [
            (s) => [s.searchParams],
            (searchParams: Record<string, unknown>): LabeledLink => toBackLink(searchParams),
        ],
        header: [
            (s) => [
                s.traceName,
                s.traceHasError,
                s.olderTraceId,
                s.olderTimestamp,
                s.newerTraceId,
                s.newerTimestamp,
                s.searchParams,
            ],
            (
                traceName: string,
                traceHasError: boolean,
                olderTraceId: string | null,
                olderTimestamp: string | null,
                newerTraceId: string | null,
                newerTimestamp: string | null,
                searchParams: Record<string, unknown>
            ): TraceHeaderProps =>
                toHeader(
                    { name: traceName, hasError: traceHasError },
                    { olderTraceId, olderTimestamp, newerTraceId, newerTimestamp },
                    searchParams
                ),
        ],
        detailData: [
            (s) => [
                s.selectedTreeNode,
                s.selectedNodeLoad,
                s.tree,
                s.evaluationResults,
                s.evaluationResultsFailed,
                s.currentTeamId,
                s.personLabel,
                s.createdAt,
                s.sessionId,
            ],
            (
                node: TraceNodeApi | null,
                load: NodeLoad,
                tree: TraceNodeApi[],
                evaluationResults: TraceEvaluationResultApi[] | null,
                evaluationResultsFailed: boolean,
                teamId: number | null,
                person: string | null,
                createdAt: string | null,
                sessionId: string | null
            ): NodeDetailData | null =>
                node && createdAt
                    ? toNodeDetail({
                          node,
                          load,
                          tree,
                          evaluationResults,
                          evaluationResultsFailed,
                          teamId,
                          person,
                          trace: { createdAt, sessionId },
                      })
                    : null,
        ],
        datasetItemSource: [
            (s, p) => [s.featureFlags, s.selectedNodeLoad, s.createdAt, p.traceId],
            (
                featureFlags: FeatureFlagsSet,
                load: NodeLoad,
                createdAt: string | null,
                traceId: string
            ): SaveToDatasetButtonProps | null =>
                featureFlags[FEATURE_FLAGS.LLM_ANALYTICS_DATASETS] && createdAt
                    ? toDatasetItemSource({ traceId, createdAt, load })
                    : null,
        ],
        thread: [
            (s, p) => [s.status, s.threadNodeLoad, s.createdAt, s.currentTeamId, p.traceId],
            (
                status: TraceViewStatus,
                load: NodeLoad | null,
                createdAt: string | null,
                teamId: number | null,
                traceId: string
            ): ConversationState => {
                if (status !== 'ready' || !createdAt) {
                    return { status: 'loading' }
                }
                return toThread({ traceId, createdAt, load, teamId })
            },
        ],
        canViewInThread: [
            (s, p) => [s.selectedNodeId, s.threadNodeIds, p.traceId],
            (selectedNodeId: string, threadNodeIds: string[], traceId: string): boolean =>
                selectedNodeId === traceId || threadNodeIds.includes(selectedNodeId),
        ],
        // Results of an older query stay in the loader while a newer one loads or after it fails.
        readySearchResults: [
            (s) => [s.searchStatus, s.searchResults],
            (status: TraceSearchStatus, results: TraceSearchResultsApi | null): TraceSearchResultsApi | null =>
                status === 'ready' ? results : null,
        ],
        // Only Spans shows the selected step, so in other modes it is no place to count or step from.
        shownSelectedNodeId: [
            (s) => [s.mode, s.selectedNodeId],
            (mode: TraceMode, selectedNodeId: string): string | null => (mode === 'spans' ? selectedNodeId : null),
        ],
        searchBox: [
            (s) => [s.query, s.searchStatus, s.readySearchResults, s.searchFailure, s.shownSelectedNodeId],
            (
                query: string,
                status: TraceSearchStatus,
                results: TraceSearchResultsApi | null,
                failure: TraceSearchFailure | null,
                shownSelectedNodeId: string | null
            ): TraceSearchBoxData => toSearchBox(query, status, results, failure, shownSelectedNodeId),
        ],
        matchingNodeIds: [
            (s) => [s.readySearchResults],
            (results: TraceSearchResultsApi | null): ReadonlySet<string> | null => toMatchingNodeIds(results),
        ],
        highlightQuery: [
            (s) => [s.query, s.searchStatus],
            (query: string, status: TraceSearchStatus): string | null => (status === 'ready' ? query.trim() : null),
        ],
    }),
    listeners(({ actions, values, props }) => {
        // The click's read starts before the selection moves, so the selectedNodeId subscription's navigation read
        // for the same id is deduped and the load event reports a click. Selecting the node that is already
        // selected changes no value and the subscription does not fire, so this read also retries a failed node.
        // The legacy logic resets its selection from the URL on every location change, so a URL that carries the
        // search carries the selection too. Each change also records a product intent there.
        const writeUrl = (query: string): void => {
            router.actions.replace(
                urls.aiObservabilityTrace(props.traceId),
                { ...values.searchParams, search: query || undefined, event: values.eventId ?? undefined },
                router.values.hashParams
            )
        }
        const select = ({ id }: { id: string }): void => {
            actions.loadNode(id, 'selection')
            actions.setEventId(id)
            if (values.query.trim() && values.searchParams.event !== id) {
                writeUrl(values.query)
            }
        }
        return {
            selectNode: select,
            selectAndShowSpans: select,
            prefetchNode: async ({ id }, breakpoint) => {
                await breakpoint(PREFETCH_DELAY_MS)
                actions.loadNode(id, 'prefetch')
            },
            loadTraceSuccess: ({ trace }) => actions.loadNeighbors(props.traceId, trace.createdAt),
            stepMatch: ({ direction }) => {
                const matches = values.readySearchResults?.matches ?? []
                const id = steppedMatchId(matches, values.shownSelectedNodeId, direction)
                if (id) {
                    actions.selectAndShowSpans(id)
                }
            },
            // The URL follows the debounced query rather than each keystroke.
            setQuery: async ({ query }, breakpoint) => {
                await breakpoint(SEARCH_DEBOUNCE_MS)
                if (String(values.searchParams.search ?? '') !== query) {
                    writeUrl(query)
                }
            },
        }
    }),
    urlToAction(({ actions, values, props }) => ({
        [`${urls.aiObservabilityTraces()}/:id`]: ({ id }, { search }) => {
            const query = search === undefined || search === null ? '' : String(search)
            if (tryDecodeURIComponent(id ?? '') === props.traceId && query !== values.query) {
                actions.setQuery(query)
            }
        },
    })),
    subscriptions(({ actions }) => ({
        selectedNodeId: (selectedNodeId: string) => actions.loadNode(selectedNodeId, 'navigation'),
    })),
])
