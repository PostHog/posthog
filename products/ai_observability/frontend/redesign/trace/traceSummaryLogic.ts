export type traceSummaryLogicType = MakeLogicType<
    traceSummaryLogicValues,
    traceSummaryLogicActions,
    TraceSummaryLogicProps,
    traceSummaryLogicMeta
>

export const traceSummaryLogic = kea<traceSummaryLogicType>([
    props({} as TraceSummaryLogicProps),
    key((props) => props.traceId),
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceSummaryLogic', key]),
    connect(() => ({
        values: [aiConsentLogic, ['dataProcessingAccepted']],
    })),
    actions({
        openSummary: (openedFrom: SummaryOpenedFrom) => ({ openedFrom }),
        closeSummary: true,
        pollScheduled: true,
        summaryShownTracked: (generatedAt: string) => ({ generatedAt }),
    }),
    loaders(({ props }) => ({
        entry: [
            null as TraceSummaryApi | null,
            {
                loadSummary: async (_: void, breakpoint): Promise<TraceSummaryApi | null> => {
                    const read = readSummary(props.traceId)
                    // A read from an earlier visit can land after a newer read and a request. Settling before the
                    // breakpoint drops it whether it succeeded or failed, so it never replaces a newer entry.
                    await read.catch(() => null)
                    breakpoint()
                    return await read
                },
                requestSummary: async ({ regenerate, timestampHint }: SummaryRequest): Promise<TraceSummaryApi> =>
                    await aiObservabilityTracesSummaryCreate(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        { regenerate },
                        timestampHint ? { timestamp_hint: timestampHint } : undefined
                    ),
            },
        ],
    })),
    reducers({
        isOpen: [false, { openSummary: () => true, closeSummary: () => false }],
        openedFrom: ['tab' as SummaryOpenedFrom, { openSummary: (_, { openedFrom }) => openedFrom }],
        pollDelayMs: [
            FIRST_POLL_DELAY_MS,
            {
                openSummary: () => FIRST_POLL_DELAY_MS,
                requestSummary: () => FIRST_POLL_DELAY_MS,
                pollScheduled: (delay) => Math.min(delay * POLL_BACKOFF, MAX_POLL_DELAY_MS),
            },
        ],
        // Cleared on an answer rather than on the request, so a reload keeps the error on screen until it lands.
        entryFailed: [
            false,
            {
                openSummary: () => false,
                loadSummarySuccess: () => false,
                loadSummaryFailure: () => true,
            },
        ],
        // A failed request leaves the entry as it was, so the view keeps showing it next to this error.
        requestError: [
            null as SummaryRequestError | null,
            {
                openSummary: () => null,
                requestSummary: () => null,
                requestSummaryFailure: (_, { errorObject }) =>
                    errorObject instanceof ApiError && errorObject.status === 429 ? 'throttled' : 'failed',
            },
        ],
        firstLoadDone: [
            false,
            {
                openSummary: () => false,
                loadSummarySuccess: () => true,
                loadSummaryFailure: () => true,
            },
        ],
        requesting: [
            false,
            {
                requestSummary: () => true,
                requestSummarySuccess: () => false,
                requestSummaryFailure: () => false,
            },
        ],
        // Kept across visits until a summary is shown, so one that finished while the mode was closed still counts
        // as just generated.
        sawPending: [
            false,
            {
                summaryShownTracked: () => false,
                loadSummarySuccess: (state, { entry }) => state || entry?.status === 'pending',
                requestSummarySuccess: (state, { entry }) => state || entry?.status === 'pending',
            },
        ],
        shownGeneratedAt: [null as string | null, { summaryShownTracked: (_, { generatedAt }) => generatedAt }],
    }),
    selectors({
        state: [
            (s) => [s.entry, s.entryFailed, s.firstLoadDone],
            (entry: TraceSummaryApi | null, entryFailed: boolean, firstLoadDone: boolean): SummaryModeState => {
                if (entryFailed) {
                    return { status: 'error' }
                }
                if (!firstLoadDone) {
                    return { status: 'loading' }
                }
                if (!entry) {
                    return { status: 'none' }
                }
                if (entry.status === 'ready' && entry.content) {
                    return { status: 'ready', summary: entry.content }
                }
                if (entry.status === 'failed' && entry.failure) {
                    return {
                        status: 'failed',
                        message: entry.failure.message,
                        retryable: !FINAL_FAILURE_REASONS.has(entry.failure.reason),
                    }
                }
                return entry.status === 'pending' ? { status: 'pending' } : { status: 'error' }
            },
        ],
        canGenerate: [
            (s) => [s.dataProcessingAccepted],
            (dataProcessingAccepted: boolean): boolean =>
                dataProcessingAccepted &&
                userHasAccess(AccessControlResourceType.LlmAnalytics, AccessControlLevel.Editor),
        ],
    }),
    listeners(({ actions, values, cache, selectors }) => {
        const pollWhilePending = (): void => {
            if (!values.isOpen || values.state.status !== 'pending') {
                cache.disposables.dispose('summaryPoll')
                return
            }
            const delay = values.pollDelayMs
            actions.pollScheduled()
            cache.disposables.add(() => {
                const timeout = window.setTimeout(() => actions.loadSummary(), delay)
                return () => window.clearTimeout(timeout)
            }, 'summaryPoll')
        }
        const trackShown = (): void => {
            const { state } = values
            if (values.isOpen && state.status === 'ready' && state.summary.generatedAt !== values.shownGeneratedAt) {
                posthog.capture('llma trace view summary shown', {
                    source: values.sawPending ? 'just_generated' : 'stored',
                })
                actions.summaryShownTracked(state.summary.generatedAt)
            }
        }
        const answered = (): void => {
            pollWhilePending()
            trackShown()
        }
        return {
            openSummary: () => {
                cache.disposables.dispose('summaryPoll')
                actions.loadSummary()
            },
            closeSummary: () => {
                cache.disposables.dispose('summaryPoll')
            },
            loadSummarySuccess: (_, __, ___, previousState) => {
                if (values.isOpen && !selectors.firstLoadDone(previousState)) {
                    posthog.capture('llma trace view summary viewed', {
                        has_summary: values.entry !== null,
                        status: values.state.status,
                        can_generate: values.canGenerate,
                        opened_from: values.openedFrom,
                    })
                }
                answered()
            },
            requestSummary: ({ regenerate }) => {
                posthog.capture('llma trace view summary requested', { regenerate })
            },
            requestSummarySuccess: answered,
        }
    }),
])
