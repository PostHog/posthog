import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { ApiConfig, ApiError } from 'lib/api'

import { aiObservabilityTracesSearchRetrieve } from '../../generated/api'
import type { TraceSearchResultsApi } from '../../generated/api.schemas'
import { encodeTraceIdSegment } from './traceIdSegment'
import { elapsedMs, traceViewLogic } from './traceViewLogic'
import type { TraceSearchFailure, TraceSearchStatus } from './types'

export interface TraceSearchLogicProps {
    traceId: string
    timestampHint: string | null
}

export const SEARCH_DEBOUNCE_MS = 300

function toSearchFailure(error: unknown): TraceSearchFailure {
    return error instanceof ApiError && error.status === 504 ? 'too_slow' : 'failed'
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceSearchLogicValues {
    createdAt: string | null // traceViewLogic
    query: string
    searchFailure: TraceSearchFailure | null
    searchResults: TraceSearchResultsApi | null
    searchResultsLoading: boolean
    searchStatus: TraceSearchStatus
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceSearchLogicActions {
    loadTraceSuccess: (
        trace: import('../../generated/api.schemas').TraceApi,
        payload?: any
    ) => {
        payload?: any
        trace: import('../../generated/api.schemas').TraceApi
    } // traceViewLogic
    loadSearchResults: (_: void) => void
    loadSearchResultsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSearchResultsSuccess: (
        searchResults: TraceSearchResultsApi | null,
        payload?: void
    ) => {
        searchResults: TraceSearchResultsApi | null
        payload?: void
    }
    setQuery: (query: string) => {
        query: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceSearchLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        searchStatus: (
            query: string,
            searchFailure: TraceSearchFailure | null,
            searchResults: TraceSearchResultsApi | null,
            searchResultsLoading: boolean
        ) => TraceSearchStatus
    }
}

export type traceSearchLogicType = MakeLogicType<
    traceSearchLogicValues,
    traceSearchLogicActions,
    TraceSearchLogicProps,
    traceSearchLogicMeta
>

export const traceSearchLogic = kea<traceSearchLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceSearchLogic', key]),
    props({} as TraceSearchLogicProps),
    key((props) => props.traceId),
    connect((props: TraceSearchLogicProps) => ({
        values: [traceViewLogic({ traceId: props.traceId, timestampHint: props.timestampHint }), ['createdAt']],
        actions: [traceViewLogic({ traceId: props.traceId, timestampHint: props.timestampHint }), ['loadTraceSuccess']],
    })),
    actions({
        setQuery: (query: string) => ({ query }),
    }),
    reducers({
        query: ['', { setQuery: (_, { query }) => query }],
    }),
    loaders(({ props, values, cache }) => ({
        searchResults: [
            null as TraceSearchResultsApi | null,
            {
                loadSearchResults: async (_: void, breakpoint): Promise<TraceSearchResultsApi | null> => {
                    const query = values.query.trim()
                    const createdAt = values.createdAt
                    if (!query || !createdAt) {
                        return null
                    }
                    await breakpoint(SEARCH_DEBOUNCE_MS)
                    // Each search scans the whole trace in ClickHouse, and a request the user moved past keeps running
                    // on the server, so the box sends the latest query only after the previous request answers.
                    await cache.searchInFlight
                    breakpoint()
                    cache.searchRequestedAt = performance.now()
                    const request = aiObservabilityTracesSearchRetrieve(
                        String(ApiConfig.getCurrentProjectId()),
                        encodeTraceIdSegment(props.traceId),
                        { q: query, timestamp_hint: createdAt }
                    )
                    cache.searchInFlight = request.then(
                        () => undefined,
                        () => undefined
                    )
                    const results = await request.catch((error: unknown) => {
                        // A superseded request must not show its failure on the newer query.
                        breakpoint()
                        throw error
                    })
                    breakpoint()
                    return results
                },
            },
        ],
    })),
    reducers({
        searchFailure: [
            null as TraceSearchFailure | null,
            {
                loadSearchResults: () => null,
                loadSearchResultsFailure: (_, { errorObject }) => toSearchFailure(errorObject),
            },
        ],
    }),
    selectors({
        searchStatus: [
            (s) => [s.query, s.searchFailure, s.searchResults, s.searchResultsLoading],
            (
                query: string,
                failure: TraceSearchFailure | null,
                results: TraceSearchResultsApi | null,
                loading: boolean
            ): TraceSearchStatus => {
                if (!query.trim()) {
                    return 'idle'
                }
                if (failure) {
                    return 'error'
                }
                return loading || !results ? 'loading' : 'ready'
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setQuery: () => actions.loadSearchResults(),
        loadSearchResultsSuccess: ({ searchResults }) => {
            if (searchResults) {
                posthog.capture('llma trace view searched', {
                    query_length: values.query.trim().length,
                    total: searchResults.total,
                    matching_steps: searchResults.matches.length,
                    load_ms: elapsedMs(cache.searchRequestedAt),
                })
            }
        },
        loadTraceSuccess: () => {
            if (values.query.trim()) {
                actions.loadSearchResults()
            }
        },
    })),
])
