const LOADING: NodeLoad = { status: 'loading' }
// Skimming the tree with the pointer must not start a read for every row it crosses.
const PREFETCH_DELAY_MS = 75

export const traceViewModelLogic = kea<traceViewModelLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceViewModelLogic', key]),
    props({} as TraceViewModelLogicProps),
    key((props) => `${props.hostId}/${props.traceId}`),
    connect((props: TraceViewModelLogicProps) => ({
        values: [
            traceViewLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['status', 'nodes', 'rawNodes', 'createdAt', 'nodeIdsByAlias', 'evalOutcomes', 'trace'],
            traceViewHostLogic({ hostId: props.hostId }),
            ['mode', 'detailTab', 'requestedStepId', 'requestedTraceId', 'openingMode', 'seedQuery'],
            traceFeedbackLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['traceFeedback', 'stepFeedback'],
            traceSearchLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['query', 'searchStatus', 'searchFailure', 'readySearchResults'],
            traceSummaryLogic({ traceId: props.traceId }),
            ['isOpen as summaryIsOpen'],
        ],
        actions: [
            traceViewHostLogic({ hostId: props.hostId }),
            ['setMode as setHostMode', 'setDetailTab as setHostDetailTab', 'requestStep', 'publishQuery'],
            traceViewLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['loadNode', 'loadRawNode', 'loadTraceSuccess'],
            traceClustersLogic({ traceId: props.traceId }),
            ['loadClusters'],
            traceFeedbackLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['retryTraceFeedback'],
            traceSearchLogic({ traceId: props.traceId, timestampHint: props.timestampHint }),
            ['setQuery'],
            traceSummaryLogic({ traceId: props.traceId }),
            ['openSummary', 'closeSummary', 'requestSummary', 'loadSummary'],
        ],
    })),
    actions({
        setMode: (mode: TraceMode) => ({ mode }),
        setDetailTab: (tab: NodeDetailTab) => ({ tab }),
        selectNode: (id: string) => ({ id }),
        selectAndShowSpans: (id: string) => ({ id }),
        viewInThread: true,
        prefetchNode: (id: string) => ({ id }),
        showFailingEvals: true,
        showFeedback: (nodeId: string | null, entry: FeedbackEntry) => ({ nodeId, entry }),
        stepMatch: (direction: MatchDirection) => ({ direction }),
        openSummaryFromLink: true,
        summarize: true,
        regenerateSummary: true,
        summaryStepClicked: (nodeId: string, kind: SummaryItemKind) => ({ nodeId, kind }),
    }),
    reducers({
        feedbackFocusNodeId: [
            null as string | null,
            {
                showFeedback: (_, { nodeId }) => nodeId,
                setMode: (focusNodeId, { mode }) => (mode === 'feedback' ? focusNodeId : null),
                selectAndShowSpans: () => null,
                viewInThread: () => null,
            },
        ],
        matchStepCount: [0, { stepMatch: (count) => count + 1 }],
    }),
    selectors({
        selectedNodeId: [
            (s, p) => [s.requestedStepId, s.openingMode, s.trace, s.nodeIdsByAlias, p.traceId],
            (
                requestedStepId: string | null,
                openingMode: TraceOpeningMode,
                trace: TraceApi | null,
                nodeIdsByAlias: ReadonlyMap<string, string>,
                traceId: string
            ): string => {
                if (!trace) {
                    return requestedStepId ?? traceId
                }
                if (!requestedStepId) {
                    // Trace-level links from clusters and sessions ask for the trace itself in the Summary mode.
                    return openingMode === 'summary' ? traceId : trace.defaultNodeId
                }
                if (findTreeNode(trace.tree, requestedStepId)) {
                    return requestedStepId
                }
                return nodeIdsByAlias.get(requestedStepId) ?? traceId
            },
        ],
        // Until the trace names its default step, only a step the URL asks for is worth reading.
        nodeIdToRead: [
            (s) => [s.status, s.requestedStepId, s.selectedNodeId],
            (status: TraceViewStatus, requestedStepId: string | null, selectedNodeId: string): string | null =>
                status === 'ready' || requestedStepId ? selectedNodeId : null,
        ],
        selectedTreeNode: [
            (s) => [s.trace, s.selectedNodeId],
            (trace: TraceApi | null, selectedNodeId: string): TraceNodeApi | null =>
                trace ? findTreeNode(trace.tree, selectedNodeId) : null,
        ],
        // Each consumer reads its own node load, so a prefetch of another node does not rebuild its heavy messages.
        selectedNodeLoad: [
            (s) => [s.selectedNodeId, s.nodes],
            (selectedNodeId: string, nodes: ReadonlyMap<string, NodeLoad>): NodeLoad =>
                nodes.get(selectedNodeId) ?? LOADING,
        ],
        selectedRaw: [
            (s) => [s.selectedNodeId, s.rawNodes],
            (selectedNodeId: string, rawNodes: ReadonlyMap<string, RawLoad>): RawLoad | undefined =>
                rawNodes.get(selectedNodeId),
        ],
        // The raw read waits for the trace's timestamp, which it sends as a hint to find steps past the ai_events retention.
        rawNodeIdToRead: [
            (s) => [s.detailTab, s.nodeIdToRead, s.createdAt],
            (detailTab: NodeDetailTab, nodeIdToRead: string | null, createdAt: string | null): string | null =>
                detailTab === 'raw' && createdAt ? nodeIdToRead : null,
        ],
        threadNodeLoad: [
            (s) => [s.trace, s.nodes],
            (trace: TraceApi | null, nodes: ReadonlyMap<string, NodeLoad>): NodeLoad | null => {
                const threadNodeId = trace?.threadNodeIds[0]
                return threadNodeId ? (nodes.get(threadNodeId) ?? LOADING) : null
            },
        ],
        thread: [
            (s, p) => [s.status, s.threadNodeLoad, s.createdAt, p.traceId],
            (
                status: TraceViewStatus,
                load: NodeLoad | null,
                createdAt: string | null,
                traceId: string
            ): ConversationState => {
                if (status !== 'ready' || !createdAt) {
                    return { status: 'loading' }
                }
                return toThread({ traceId, createdAt, load })
            },
        ],
        canViewInThread: [
            (s, p) => [s.selectedNodeId, s.trace, p.traceId],
            (selectedNodeId: string, trace: TraceApi | null, traceId: string): boolean =>
                selectedNodeId === traceId || !!trace?.threadNodeIds.includes(selectedNodeId),
        ],
        selectedStepFeedback: [
            (s) => [s.stepFeedback, s.selectedNodeId],
            (
                stepFeedback: ReadonlyMap<string, TraceStepFeedbackApi>,
                selectedNodeId: string
            ): TraceStepFeedbackApi | null => stepFeedback.get(selectedNodeId) ?? null,
        ],
        // Only Spans shows the selected step, so in other modes it is no place to count or step from.
        shownSelectedNodeId: [
            (s) => [s.mode, s.selectedNodeId],
            (mode: TraceMode, selectedNodeId: string): string | null => (mode === 'spans' ? selectedNodeId : null),
        ],
        searchBox: [
            (s) => [s.query, s.searchStatus, s.readySearchResults, s.searchFailure, s.shownSelectedNodeId],
            (
                query: string,
                status: TraceSearchStatus,
                results: TraceSearchResultsApi | null,
                failure: TraceSearchFailure | null,
                shownSelectedNodeId: string | null
            ): TraceSearchBoxData => toSearchBox(query, status, results, failure, shownSelectedNodeId),
        ],
    }),
    listeners(({ actions, values, props }) => {
        // The click's read starts before the selection moves, so the nodeIdToRead subscription's navigation read
        // for the same id is deduped and the load event reports a click. Selecting the node that is already
        // selected changes no value and the subscription does not fire, so this read also retries a failed node.
        const select = ({ id }: { id: string }): void => {
            actions.loadNode(id, 'selection')
            if (values.detailTab === 'raw' || values.rawNodes.get(id)?.status === 'error') {
                actions.loadRawNode(id)
            }
            actions.requestStep(id, props.traceId)
        }
        const captureFeedbackViewed = (entry: FeedbackEntry | 'tab'): void => {
            traceViewTracking.feedbackViewed(entry, {
                scores: values.traceFeedback?.scores.length ?? null,
                responses: values.traceFeedback?.responses.length ?? null,
                unanswered: values.traceFeedback?.unanswered.length ?? null,
            })
        }
        const requestSummary = (regenerate: boolean): void => {
            actions.requestSummary({ regenerate, timestampHint: values.createdAt })
        }
        return {
            viewInThread: () => actions.setHostMode('thread'),
            selectNode: select,
            selectAndShowSpans: (payload) => {
                select(payload)
                actions.setHostMode('spans')
            },
            prefetchNode: async ({ id }, breakpoint) => {
                await breakpoint(PREFETCH_DELAY_MS)
                actions.loadNode(id, 'prefetch')
            },
            loadTraceSuccess: ({ trace }) => {
                actions.loadClusters(trace.createdAt)
                // Cluster and session pages link to a trace in the Summary mode. The mode opens without generating.
                // A link that also names a step opens that step, because the Summary mode covers the whole trace.
                if (values.openingMode === 'summary' && values.mode !== 'summary' && !values.requestedStepId) {
                    actions.openSummaryFromLink()
                }
            },
            openSummaryFromLink: () => {
                actions.openSummary('link')
                actions.setHostMode('summary')
            },
            summarize: () => requestSummary(false),
            regenerateSummary: () => requestSummary(true),
            summaryStepClicked: ({ nodeId, kind }) => {
                traceViewTracking.summaryStepClicked(kind)
                actions.selectAndShowSpans(nodeId)
            },
            stepMatch: ({ direction }) => {
                const matches = values.readySearchResults?.matches ?? []
                const id = steppedMatchId(matches, values.shownSelectedNodeId, direction)
                if (id) {
                    actions.selectAndShowSpans(id)
                }
            },
            // The host follows the debounced query rather than each keystroke.
            setQuery: async ({ query }, breakpoint) => {
                await breakpoint(SEARCH_DEBOUNCE_MS)
                actions.publishQuery(query)
            },
            showFailingEvals: () => {
                actions.selectAndShowSpans(
                    firstFailingNodeId(values.trace?.tree ?? [], values.evalOutcomes) ?? props.traceId
                )
                actions.setDetailTab('evals')
            },
            showFeedback: ({ entry }) => {
                captureFeedbackViewed(entry)
                actions.setHostMode('feedback')
            },
            setMode: ({ mode }) => {
                const previousMode = values.mode
                actions.setHostMode(mode)
                if (mode === 'feedback' && previousMode !== 'feedback') {
                    captureFeedbackViewed('tab')
                }
            },
            setDetailTab: ({ tab }) => actions.setHostDetailTab(tab),
        }
    }),
    subscriptions(({ actions, props, values }) => ({
        nodeIdToRead: (nodeIdToRead: string | null) => {
            // A drawer requests the next trace's step before this view unmounts. That step is not a node of this trace.
            if (
                nodeIdToRead === null ||
                (values.requestedTraceId !== null && values.requestedTraceId !== props.traceId)
            ) {
                return
            }
            actions.loadNode(nodeIdToRead, 'navigation')
        },
        rawNodeIdToRead: (rawNodeIdToRead: string | null) => {
            if (rawNodeIdToRead === null) {
                return
            }
            if (values.requestedTraceId === null || values.requestedTraceId === props.traceId) {
                actions.loadRawNode(rawNodeIdToRead)
            }
        },
        mode: (mode: TraceMode) => {
            if (mode === 'summary' && !values.summaryIsOpen) {
                actions.openSummary('tab')
            } else if (mode !== 'summary' && values.summaryIsOpen) {
                actions.closeSummary()
            }
        },
        seedQuery: (seedQuery: string) => {
            if (seedQuery !== values.query) {
                actions.setQuery(seedQuery)
            }
        },
    })),
])
