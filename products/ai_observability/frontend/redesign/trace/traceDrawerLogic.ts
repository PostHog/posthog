export const traceDrawerLogic = kea<traceDrawerLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'trace', 'traceDrawerLogic', key]),
    props({} as TraceDrawerLogicProps),
    key((props) => props.listId),
    connect((props: TraceDrawerLogicProps) => ({
        values: [
            traceViewHostLogic({ hostId: traceDrawerHostId(props.listId) }),
            ['requestedStepId'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [
            traceViewHostLogic({ hostId: traceDrawerHostId(props.listId) }),
            ['requestStep', 'setMode', 'setDetailTab', 'setOpeningMode'],
        ],
    })),
    actions({
        setRows: (rows: TraceListRow[]) => ({ rows }),
        openRow: (row: TraceListRow) => ({ row }),
        stepTo: (direction: TraceStepDirection) => ({ direction }),
        close: true,
    }),
    reducers({
        rows: [
            [] as TraceListRow[],
            {
                setRows: (_, { rows }) => rows,
            },
        ],
    }),
    selectors({
        hostId: [(_, p) => [p.listId], (listId: string): string => traceDrawerHostId(listId)],
        isEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.AI_OBSERVABILITY_TRACE_REDESIGN],
        ],
        openRef: [
            (_, p) => [router.selectors.location, p.listId],
            (
                { pathname, search }: { pathname: string; search: string },
                listId: TraceDrawerListId
            ): TraceListRow | null => {
                const isOwnPath = TRACE_DRAWER_LISTS[listId].pathMatcher.test(removeProjectIdIfPresent(pathname))
                const traceId = isOwnPath ? rawSearchParam(search, 'trace') : null
                return traceId
                    ? { traceId, timestamp: rawSearchParam(search, 'ts'), stepId: rawSearchParam(search, 'step') }
                    : null
            },
        ],
        openTraceId: [(s) => [s.openRef], (openRef: TraceListRow | null): string | null => openRef?.traceId ?? null],
        traces: [(s) => [s.rows], (rows: TraceListRow[]): TraceListRow[] => uniqueTraces(rows)],
        openIndex: [
            (s) => [s.traces, s.openTraceId],
            (traces: TraceListRow[], openTraceId: string | null): number =>
                traces.findIndex(({ traceId }) => traceId === openTraceId),
        ],
        position: [
            (s) => [s.traces, s.openIndex],
            (traces: TraceListRow[], openIndex: number): TraceDrawerPosition | null =>
                openIndex < 0 ? null : { index: openIndex, total: traces.length },
        ],
        previousTrace: [
            (s) => [s.traces, s.openIndex],
            (traces: TraceListRow[], openIndex: number): TraceListRow | null =>
                openIndex < 0 ? null : (traces[openIndex - 1] ?? null),
        ],
        nextTrace: [
            (s) => [s.traces, s.openIndex],
            (traces: TraceListRow[], openIndex: number): TraceListRow | null =>
                openIndex < 0 ? null : (traces[openIndex + 1] ?? null),
        ],
        fullPageHref: [
            (s, p) => [
                s.openRef,
                s.requestedStepId,
                p.listId,
                router.selectors.location,
                router.selectors.searchParams,
            ],
            (
                openRef: TraceListRow | null,
                requestedStepId: string | null,
                listId: TraceDrawerListId,
                location: { pathname: string; search: string },
                searchParams: Record<string, unknown>
            ): string | null =>
                openRef && toFullPageUrl(openRef, requestedStepId, TRACE_DRAWER_LISTS[listId], location, searchParams),
        ],
    }),
    listeners(({ actions, cache, values }) => ({
        openRow: ({ row }) => {
            if (row.traceId !== values.openTraceId) {
                writeUrlParams('push', toDrawerParams(row))
            } else if (row.stepId !== null) {
                // A row with no step of its own would otherwise clear the selected step.
                actions.requestStep(row.stepId, row.traceId)
            }
        },
        stepTo: ({ direction }) => {
            const target = direction === 'next' ? values.nextTrace : values.previousTrace
            if (target) {
                cache.stepsTaken += 1
                traceViewTracking.drawerStepped(direction)
                writeUrlParams('push', toDrawerParams(target))
            }
        },
        close: () => {
            writeUrlParams('push', toDrawerParams(null))
        },
        requestStep: ({ stepId }) => {
            if (values.openRef && values.openRef.stepId !== stepId) {
                writeUrlParams('replace', { step: stepId ?? undefined })
            }
        },
    })),
    subscriptions(({ actions, cache, props, values }) => ({
        openRef: (openRef: TraceListRow | null, previousRef: TraceListRow | null | undefined) => {
            if (openRef && previousRef && isNumberRewriteOf(openRef, previousRef)) {
                writeUrlParams('replace', toDrawerParams(previousRef))
                return
            }
            if (!openRef) {
                trackDrawerClosed(cache)
                return
            }
            const config = TRACE_DRAWER_LISTS[props.listId]
            actions.requestStep(openRef.stepId, openRef.traceId)
            if (!values.isEnabled) {
                const { location, searchParams } = router.values
                router.actions.replace(toFullPageUrl(openRef, openRef.stepId, config, location, searchParams))
            } else if (cache.stepsTaken === undefined) {
                cache.stepsTaken = 0
                actions.setOpeningMode(config.openingMode ?? null)
                actions.setMode('spans')
                actions.setDetailTab(config.detailTab ?? 'messages')
                traceViewTracking.drawerOpened(props.listId)
                void addProductIntent({
                    product_type: ProductKey.AI_OBSERVABILITY,
                    intent_context: ProductIntentContext.LLM_ANALYTICS_TRACE_VIEWED,
                })
                // Viewing a trace implies AI events were sent.
                globalSetupLogic
                    .findMounted()
                    ?.actions.markTaskAsCompleted([SetupTaskId.IngestFirstLlmEvent, SetupTaskId.ViewFirstTrace])
                cache.disposables.add(() => {
                    const closeOnEscape = (event: KeyboardEvent): void => {
                        if (shouldCloseOnEscape(event)) {
                            actions.close()
                        }
                    }
                    document.addEventListener('keydown', closeOnEscape)
                    return () => document.removeEventListener('keydown', closeOnEscape)
                }, CLOSE_ON_ESCAPE_DISPOSABLE)
            } else if (openRef.traceId !== previousRef?.traceId) {
                // The view applies an opening on each trace it loads, which would undo the mode the person chose.
                actions.setOpeningMode(null)
            }
        },
    })),
    beforeUnmount(({ cache, values }) => {
        // A list remounts behind its loading state on browser back, and the URL must still hold its trace.
        if (values.openRef) {
            trackDrawerClosed(cache)
        }
    }),
])
