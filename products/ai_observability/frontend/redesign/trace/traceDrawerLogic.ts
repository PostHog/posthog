export type TraceStepDirection = 'previous' | 'next'

export interface TraceDrawerPosition {
    index: number
    total: number
}

const CLOSE_ON_ESCAPE_DISPOSABLE = 'closeOnEscape'

function traceDrawerHostId(listId: string): string {
    return `trace-drawer-${listId}`
}

// kea-router loses the text of a number or boolean, so a typed `1.50` must stay raw. A JSON param such as `filters` must
// stay parsed, because kea-router pads a string shaped like JSON and reads it back as a string. The drawer's own params
// are ids, so they stay raw whatever their shape.
function keepsRawText(name: string, value: unknown): boolean {
    return TRACE_DRAWER_PARAMS.includes(name) || typeof value === 'number' || typeof value === 'boolean'
}

function withRawParams(searchParams: Record<string, unknown>, search: string): Record<string, unknown> {
    return Object.fromEntries(
        Object.entries(searchParams).map(([name, value]) => [
            name,
            keepsRawText(name, value) ? (rawSearchParam(search, name) ?? value) : value,
        ])
    )
}

function toDrawerParams(row: TraceListRow | null): Record<string, string | undefined> {
    return { trace: row?.traceId, ts: row?.timestamp ?? undefined, step: row?.stepId ?? undefined }
}

let isDrawerWriting = false

function writeUrlParams(method: 'push' | 'replace', changes: Record<string, string | undefined>): void {
    const { pathname, search } = router.values.location
    isDrawerWriting = true
    try {
        router.actions[method](
            pathname,
            { ...withRawParams(router.values.searchParams, search), ...changes },
            router.values.hashParams
        )
    } finally {
        isDrawerWriting = false
    }
}

// Other logics write the router's decoded params back to the URL, and the router decodes `1.50` as the number 1.5.
// The drawer's own writes and browser history moves are navigation, even between ids such as `01` and `1`.
function isNumberRewriteOf(current: TraceListRow, previous: TraceListRow): boolean {
    if (isDrawerWriting || router.values.lastMethod === 'POP') {
        return false
    }
    const pairs = [
        [previous.traceId, current.traceId],
        [previous.stepId, current.stepId],
    ]
    return (
        pairs.some(([before, after]) => before !== after) &&
        pairs.every(([before, after]) => before === after || (before !== null && String(Number(before)) === after))
    )
}

function toFullPageUrl(
    { traceId, timestamp }: TraceListRow,
    stepId: string | null,
    { backTo, openingMode, detailTab }: TraceDrawerListConfig,
    { pathname, search }: { pathname: string; search: string },
    searchParams: Record<string, unknown>
): string {
    const listParams = withRawParams(searchParams, search)
    return combineUrl(urls.aiObservabilityTrace(traceId), {
        ...toFullPageListParams(listParams),
        timestamp: timestamp ?? undefined,
        event: stepId ?? undefined,
        tab: openingMode ?? detailTab,
        back_to: backTo,
        back_url: combineUrl(removeProjectIdIfPresent(pathname), withoutTraceDrawerParams(listParams)).url,
    }).url
}

function trackDrawerClosed(cache: Record<string, any>): void {
    if (cache.stepsTaken === undefined) {
        return
    }
    traceViewTracking.drawerClosed(cache.stepsTaken)
    cache.stepsTaken = undefined
    cache.disposables.dispose(CLOSE_ON_ESCAPE_DISPOSABLE)
}

