import { MakeLogicType, actions, kea, listeners, path, reducers, selectors } from 'kea'
import { router, urlToAction } from 'kea-router'

import { isValidRelativeOrAbsoluteDate } from 'lib/utils/dateFilters'

import { currentUrlWith, rawSearchParam } from '../trace/rawSearchParam'
import { SHELL_TABS } from './shellNavigation'

export interface ShellDateRange {
    dateFrom: string
    dateTo: string | null
}

const DEFAULT_DATE_RANGE: ShellDateRange = { dateFrom: '-7d', dateTo: null }

const SHELL_PATHS = [...new Set(SHELL_TABS.flatMap((tab) => [tab.path, ...tab.scopes.map((scope) => scope.path)]))]

function dateParam(search: string, name: string): string | null {
    const value = rawSearchParam(search, name)
    return value !== null && isValidRelativeOrAbsoluteDate(value) ? value : null
}

function dateRangeFromUrl(search: string, current: ShellDateRange): ShellDateRange | null {
    const dateFrom = dateParam(search, 'date_from')
    const dateTo = dateParam(search, 'date_to')
    return dateFrom === null && dateTo === null ? null : { dateFrom: dateFrom ?? current.dateFrom, dateTo }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface shellScopeLogicValues {
    dateFrom: string
    dateRange: ShellDateRange
    dateTo: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface shellScopeLogicActions {
    setDateRange: (
        dateFrom: string | null,
        dateTo: string | null
    ) => {
        dateFrom: string | null
        dateTo: string | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface shellScopeLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        dateFrom: (dateRange: ShellDateRange) => string
        dateTo: (dateRange: ShellDateRange) => string | null
    }
}

export type shellScopeLogicType = MakeLogicType<
    shellScopeLogicValues,
    shellScopeLogicActions,
    Record<string, any>,
    shellScopeLogicMeta
>

export const shellScopeLogic = kea<shellScopeLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'shell', 'shellScopeLogic']),
    actions({
        setDateRange: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
    }),
    reducers({
        dateRange: [
            DEFAULT_DATE_RANGE,
            // pinned: a rename of this key resets everyone's remembered range
            { persist: true, storageKey: 'ai_observability.shell_date_range' },
            {
                setDateRange: (_, { dateFrom, dateTo }) => ({
                    dateFrom: dateFrom ?? DEFAULT_DATE_RANGE.dateFrom,
                    dateTo,
                }),
            },
        ],
    }),
    selectors({
        dateFrom: [(s) => [s.dateRange], (dateRange: ShellDateRange): string => dateRange.dateFrom],
        dateTo: [(s) => [s.dateRange], (dateRange: ShellDateRange): string | null => dateRange.dateTo],
    }),
    // pinned: `date_from` and `date_to`, which saved links and the pages behind the tabs read
    urlToAction(({ actions, values }) =>
        Object.fromEntries(
            SHELL_PATHS.map((shellPath) => [
                shellPath,
                (_: unknown, __: unknown, ___: unknown, { search }: { search: string }) => {
                    const fromUrl = dateRangeFromUrl(search, values.dateRange)
                    if (fromUrl && (fromUrl.dateFrom !== values.dateFrom || fromUrl.dateTo !== values.dateTo)) {
                        actions.setDateRange(fromUrl.dateFrom, fromUrl.dateTo)
                    }
                },
            ])
        )
    ),
    listeners(({ values }) => ({
        setDateRange: () => {
            const { search } = router.values.location
            if (dateParam(search, 'date_from') === values.dateFrom && dateParam(search, 'date_to') === values.dateTo) {
                return
            }
            router.actions.replace(
                ...currentUrlWith(router.values, { date_from: values.dateFrom, date_to: values.dateTo ?? undefined })
            )
        },
    })),
])
