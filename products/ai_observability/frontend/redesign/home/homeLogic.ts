export type HomeMetricsFailure = { kind: 'range_too_long'; detail: string } | { kind: 'error' }

function failureOf(error: unknown): HomeMetricsFailure {
    return error instanceof ApiError && error.status === 422 && error.code === 'range_too_long' && error.detail
        ? { kind: 'range_too_long', detail: error.detail }
        : { kind: 'error' }
}

