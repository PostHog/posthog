export type homeLogicType = MakeLogicType<homeLogicValues, homeLogicActions, Record<string, any>, homeLogicMeta>

export const homeLogic = kea<homeLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'home', 'homeLogic']),
    connect(() => ({
        values: [shellScopeLogic, ['dateFrom', 'dateTo', 'filterTestAccounts']],
    })),
    loaders(({ cache, values }) => ({
        metrics: [
            null as TraceMetricsApi | null,
            {
                loadMetrics: async (_: void, breakpoint): Promise<TraceMetricsApi> => {
                    cache.metricsRequestedAt = performance.now()
                    const controller = new AbortController()
                    // The next read and the unmount abort this one, so a superseded scan frees its query slot. A
                    // hidden tab keeps it, so coming back shows no failed load.
                    cache.disposables.add(() => () => controller.abort(), 'metricsRequest', {
                        pauseOnPageHidden: false,
                    })
                    const metrics = await aiObservabilityTracesMetricsList(
                        String(ApiConfig.getCurrentProjectId()),
                        values.requestParams,
                        { signal: controller.signal }
                    ).catch((error: unknown) => {
                        // A superseded request must not show its failure over the newer selection.
                        breakpoint()
                        throw error
                    })
                    breakpoint()
                    return metrics
                },
            },
        ],
        dashboardId: [
            null as number | null,
            {
                loadDashboardId: () => findAIObservabilityDashboardId(),
            },
        ],
    })),
    reducers({
        metrics: {
            loadMetricsFailure: () => null,
        },
        metricsFailure: [
            null as HomeMetricsFailure | null,
            {
                loadMetrics: () => null,
                loadMetricsFailure: (_, { errorObject }) => failureOf(errorObject),
            },
        ],
    }),
    selectors({
        requestParams: [
            (s) => [s.dateFrom, s.dateTo, s.filterTestAccounts],
            (
                dateFrom: string,
                dateTo: string | null,
                filterTestAccounts: boolean
            ): AiObservabilityTracesMetricsListParams => ({
                date_from: dateFrom,
                date_to: dateTo ?? undefined,
                filter_test_accounts: filterTestAccounts,
            }),
        ],
        tileLinks: [
            (s) => [s.dateFrom, s.dateTo, s.filterTestAccounts],
            (
                dateFrom: string,
                dateTo: string | null,
                filterTestAccounts: boolean
            ): Partial<Record<TraceMetricKeyApi, string>> => {
                const range = {
                    date_from: dateFrom,
                    date_to: dateTo ?? undefined,
                    filter_test_accounts: filterTestAccounts,
                }
                return {
                    [TraceMetricKeyApi.Traces]: combineUrl(urls.aiObservabilityTraces(), range).url,
                    [TraceMetricKeyApi.ErrorRate]: combineUrl(urls.aiObservabilityTraces(), {
                        ...range,
                        view: AiObservabilityTracesListView.Errors,
                    }).url,
                }
            },
        ],
    }),
    listeners(({ cache, values }) => ({
        loadMetricsSuccess: () => {
            homeTracking.metricsLoaded({
                loadMs: Math.round(performance.now() - cache.metricsRequestedAt),
                dateFrom: values.dateFrom,
                dateTo: values.dateTo,
                filterTestAccounts: values.filterTestAccounts,
            })
        },
    })),
    // Fires on mount with the settled range, then on each change of the range or the switch.
    subscriptions(({ actions }) => ({
        requestParams: () => actions.loadMetrics(),
    })),
    afterMount(({ actions }) => {
        actions.loadDashboardId()
    }),
])
