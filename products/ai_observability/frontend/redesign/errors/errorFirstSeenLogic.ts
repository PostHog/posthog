import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { ApiConfig } from 'lib/api'

import { aiObservabilityErrorsFirstSeenCreate } from '../../generated/api'
import type { AiObservabilityErrorsFirstSeenCreateParams, ErrorListApi } from '../../generated/api.schemas'
import { diagnosticsTracking } from '../diagnostics/diagnosticsTracking'
import { withFailed, withLoaded, withRequested } from '../shared/cellLoads'
import type { TraceCellLoad } from '../shared/cellLoads'
import { CellEntry, createPageCellReader } from '../shared/pageCellReader'
import { noEntries } from '../shared/readOrFailure'
import { ErrorsPageRequest, ErrorsSelectionParams, errorsListLogic } from './errorsListLogic'

export interface ErrorFirstSeen {
    firstSeen: string | null
    /** The earliest date the read covered. Occurrences before it were never read. */
    checkedFrom: string
    isNew: boolean
}

// First seen depends on the range and the test account switch only, so the list's other params never ask again.
function firstSeenParams({
    date_from,
    date_to,
    filter_test_accounts,
}: ErrorsSelectionParams): AiObservabilityErrorsFirstSeenCreateParams {
    return { date_from, date_to, filter_test_accounts }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface errorFirstSeenLogicValues {
    selectionParams: ErrorsSelectionParams // errorsListLogic
    firstSeen: ReadonlyMap<string, TraceCellLoad<ErrorFirstSeen>>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface errorFirstSeenLogicActions {
    loadErrorsPageFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    } // errorsListLogic
    loadErrorsPageSuccess: (
        page: ErrorListApi,
        payload?: ErrorsPageRequest | undefined
    ) => {
        page: ErrorListApi
        payload?: ErrorsPageRequest
    } // errorsListLogic
    reload: () => {
        value: true
    } // errorsListLogic
    selectionChanged: () => {
        value: true
    } // errorsListLogic
    firstSeenFailed: (keys: string[]) => {
        keys: string[]
    }
    firstSeenLoaded: (entries: CellEntry<ErrorFirstSeen>[]) => {
        entries: CellEntry<ErrorFirstSeen>[]
    }
    firstSeenParamsChanged: () => {
        value: true
    }
    firstSeenRequested: (keys: string[]) => {
        keys: string[]
    }
}

export type errorFirstSeenLogicType = MakeLogicType<errorFirstSeenLogicValues, errorFirstSeenLogicActions>

export const errorFirstSeenLogic = kea<errorFirstSeenLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'errors', 'errorFirstSeenLogic']),
    connect(() => ({
        values: [errorsListLogic, ['selectionParams']],
        actions: [errorsListLogic, ['loadErrorsPageSuccess', 'loadErrorsPageFailure', 'selectionChanged', 'reload']],
    })),
    actions({
        firstSeenParamsChanged: true,
        firstSeenRequested: (keys: string[]) => ({ keys }),
        firstSeenFailed: (keys: string[]) => ({ keys }),
        firstSeenLoaded: (entries: CellEntry<ErrorFirstSeen>[]) => ({ entries }),
    }),
    reducers({
        firstSeen: [
            noEntries<TraceCellLoad<ErrorFirstSeen>>(),
            {
                firstSeenParamsChanged: () => noEntries<TraceCellLoad<ErrorFirstSeen>>(),
                firstSeenRequested: (state, { keys }) => withRequested(state, keys),
                firstSeenFailed: (state, { keys }) => withFailed(state, keys),
                firstSeenLoaded: (state, { entries }) => withLoaded(state, entries),
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const reader = createPageCellReader<AiObservabilityErrorsFirstSeenCreateParams, ErrorFirstSeen>({
            cache,
            loads: () => values.firstSeen,
            paramsChanged: actions.firstSeenParamsChanged,
            requested: actions.firstSeenRequested,
            failed: (keys) => {
                actions.firstSeenFailed(keys)
                diagnosticsTracking.readFailed({ kind: 'error', read: 'first_seen' })
            },
            loaded: actions.firstSeenLoaded,
            request: async (keys, params) => {
                const { items, checkedFrom } = await aiObservabilityErrorsFirstSeenCreate(
                    String(ApiConfig.getCurrentProjectId()),
                    { keys },
                    params
                )
                return items.map(({ key, firstSeen, isNew }) => [key, { firstSeen, checkedFrom, isNew }])
            },
        })
        return {
            selectionChanged: () => reader.scopeTo(firstSeenParams(values.selectionParams)),
            // A reload shows the page again once it lands, and its first seen is read again with it.
            reload: reader.pageReloading,
            loadErrorsPageFailure: reader.pageFailed,
            loadErrorsPageSuccess: async ({ page, payload }) => {
                if (payload) {
                    await reader.pageLoaded(
                        page.results.map((item) => item.key),
                        firstSeenParams(payload.params)
                    )
                }
            },
        }
    }),
])
