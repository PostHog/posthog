import { MakeLogicType, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiConfig } from 'lib/api'
import { objectsEqual } from 'lib/utils/objects'

import { aiObservabilityErrorsNewCountRetrieve } from '../../generated/api'
import type { AiObservabilityErrorsNewCountRetrieveParams } from '../../generated/api.schemas'
import { diagnosticsTracking } from '../diagnostics/diagnosticsTracking'
import { readAbortablePage } from '../lists/cursorPaging'
import type { TraceCellLoad } from '../shared/cellLoads'
import { rangeTooLongDetail } from '../shared/rangeTooLong'
import { ErrorsSelectionParams, errorsListLogic } from './errorsListLogic'

// The count covers the whole selection, so the view and the order, which only pick and sort its rows, never ask again.
function newCountParams({
    view,
    order,
    ...params
}: ErrorsSelectionParams): AiObservabilityErrorsNewCountRetrieveParams {
    return params
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface errorNewCountLogicValues {
    selectionParams: ErrorsSelectionParams // errorsListLogic
    newCount: number | null
    newCountError: unknown
    newCountLoad: TraceCellLoad<number> | null
    newCountLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface errorNewCountLogicActions {
    reload: () => {
        value: true
    } // errorsListLogic
    selectionChanged: () => {
        value: true
    } // errorsListLogic
    loadErrorNewCount: (
        params: AiObservabilityErrorsNewCountRetrieveParams
    ) => AiObservabilityErrorsNewCountRetrieveParams
    loadErrorNewCountFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadErrorNewCountSuccess: (
        newCount: number,
        payload?: AiObservabilityErrorsNewCountRetrieveParams
    ) => {
        newCount: number
        payload?: AiObservabilityErrorsNewCountRetrieveParams
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface errorNewCountLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        newCountLoad: (
            newCount: number | null,
            newCountLoading: boolean,
            newCountError: unknown
        ) => TraceCellLoad<number> | null
    }
}

export type errorNewCountLogicType = MakeLogicType<
    errorNewCountLogicValues,
    errorNewCountLogicActions,
    Record<string, any>,
    errorNewCountLogicMeta
>

export const errorNewCountLogic = kea<errorNewCountLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'errors', 'errorNewCountLogic']),
    connect(() => ({
        values: [errorsListLogic, ['selectionParams']],
        actions: [errorsListLogic, ['selectionChanged', 'reload']],
    })),
    loaders(({ cache }) => ({
        newCount: [
            null as number | null,
            {
                loadErrorNewCount: async (params: AiObservabilityErrorsNewCountRetrieveParams, breakpoint) => {
                    const { count } = await readAbortablePage(
                        cache,
                        (signal) =>
                            aiObservabilityErrorsNewCountRetrieve(String(ApiConfig.getCurrentProjectId()), params, {
                                signal,
                            }),
                        breakpoint
                    )
                    return count
                },
            },
        ],
    })),
    reducers({
        newCountError: [
            null as unknown,
            {
                loadErrorNewCount: () => null,
                loadErrorNewCountFailure: (_, { errorObject }) => errorObject ?? true,
            },
        ],
    }),
    selectors({
        // Null when the range is too long, as the list's own counts are, because the list shows the range banner then.
        newCountLoad: [
            (s) => [s.newCount, s.newCountLoading, s.newCountError],
            (
                newCount: number | null,
                newCountLoading: boolean,
                newCountError: unknown
            ): TraceCellLoad<number> | null => {
                if (newCountError) {
                    return rangeTooLongDetail(newCountError) === null ? { status: 'error' } : null
                }
                return newCountLoading || newCount === null
                    ? { status: 'loading' }
                    : { status: 'ready', value: newCount }
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        selectionChanged: () => {
            const params = newCountParams(values.selectionParams)
            if (!objectsEqual(params, cache.params)) {
                cache.params = params
                actions.loadErrorNewCount(params)
            }
        },
        reload: () => {
            cache.params = newCountParams(values.selectionParams)
            actions.loadErrorNewCount(cache.params)
        },
        loadErrorNewCountFailure: ({ errorObject }) => {
            if (rangeTooLongDetail(errorObject) === null) {
                diagnosticsTracking.readFailed({ kind: 'error', read: 'new_count' })
            }
        },
    })),
    // The list reads its first selection as it mounts, before this logic listens.
    afterMount(({ actions, values, cache }) => {
        cache.params = newCountParams(values.selectionParams)
        actions.loadErrorNewCount(cache.params)
    }),
])
