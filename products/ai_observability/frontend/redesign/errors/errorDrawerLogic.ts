export const errorDrawerLogic = kea<errorDrawerLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'errors', 'errorDrawerLogic']),
    connect(() => ({
        values: [
            listFiltersLogic(ERRORS_LIST_FILTERS),
            ['filters'],
            shellScopeLogic,
            ['dateFrom', 'dateTo', 'filterTestAccounts'],
            errorFirstSeenLogic,
            ['firstSeen'],
        ],
        actions: [errorFirstSeenLogic, ['firstSeenWanted']],
    })),
    actions({
        openError: (item: ErrorListItemApi) => ({ item }),
        setSeed: (seed: EntitySeed<ErrorListItemApi>) => ({ seed }),
        close: true,
        retry: true,
        previewsRequested: (traceIds: string[]) => ({ traceIds }),
        previewsFailed: (traceIds: string[]) => ({ traceIds }),
        previewsLoaded: (items: TracePreviewApi[]) => ({ items }),
    }),
    loaders(({ cache }) => ({
        detail: [
            null as ReadFor<ErrorGroupDetailApi> | null,
            {
                loadErrorDetail: async (request: EntityRequest, breakpoint): Promise<ReadFor<ErrorGroupDetailApi>> => {
                    const value = await latest(
                        aiObservabilityErrorsRetrieve(
                            String(ApiConfig.getCurrentProjectId()),
                            request.key,
                            request.params,
                            { signal: replaceableRead(cache, DETAIL_READ) }
                        ),
                        breakpoint
                    )
                    return { request, value }
                },
            },
        ],
        recentTraces: [
            null as ReadFor<TraceListItemApi[]> | null,
            {
                loadErrorRecentTraces: async (
                    request: ErrorTracesRequest,
                    breakpoint
                ): Promise<ReadFor<TraceListItemApi[]>> => {
                    const page = await latest(
                        aiObservabilityTracesList(
                            String(ApiConfig.getCurrentProjectId()),
                            { ...request.params, error: request.message, limit: RECENT_TRACES_LIMIT },
                            { signal: replaceableRead(cache, RECENT_TRACES_READ) }
                        ),
                        breakpoint
                    )
                    return { request, value: page.items }
                },
            },
        ],
    })),
    reducers({
        seed: [
            null as EntitySeed<ErrorListItemApi> | null,
            {
                setSeed: (_, { seed }) => seed,
                close: () => null,
            },
        ],
        // An aborted read was closed or replaced, so it is no failure of what the drawer shows.
        detailFailure: [
            null as LoadFailure | null,
            {
                loadErrorDetail: () => null,
                loadErrorDetailFailure: (state, { errorObject }) =>
                    isAbortError(errorObject) ? state : toLoadFailure(errorObject),
            },
        ],
        // Another error's detail read clears the failure too, since its traces wait for its message.
        recentTracesFailed: [
            false,
            {
                loadErrorDetail: () => false,
                loadErrorRecentTraces: () => false,
                loadErrorRecentTracesFailure: (state, { errorObject }) => (isAbortError(errorObject) ? state : true),
            },
        ],
        previews: [
            noEntries<TraceCellLoad<TracePreviewApi>>() as CellLoads<TracePreviewApi>,
            {
                previewsRequested: (state, { traceIds }) => withRequested(state, traceIds),
                previewsFailed: (state, { traceIds }) => withFailed(state, traceIds),
                previewsLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.traceId, item])
                    ),
            },
        ],
    }),
    selectors({
        openKey: [
            () => [router.selectors.location],
            ({ pathname, search }: { pathname: string; search: string }): string | null =>
                removeProjectIdIfPresent(pathname) === ERRORS_LIST_FILTERS.path
                    ? entityKeyParam(rawSearchParam(search, ERROR_PARAM))
                    : null,
        ],
        readParams: [
            (s) => [s.filters, s.dateFrom, s.dateTo, s.filterTestAccounts],
            (
                filters: ListFilters,
                dateFrom: string,
                dateTo: string | null,
                filterTestAccounts: boolean
            ): DiagnosticsDrawerParams => drawerReadParams(filters, { dateFrom, dateTo, filterTestAccounts }),
        ],
        request: [
            (s) => [s.openKey, s.readParams],
            (openKey: string | null, readParams: DiagnosticsDrawerParams): EntityRequest | null =>
                openKey ? { key: openKey, params: readParams } : null,
        ],
        // A key names one message in every selection, so the message of any read of the key is the open error's.
        openMessage: [
            (s) => [s.openKey, s.seed, s.detail],
            (
                openKey: string | null,
                seed: EntitySeed<ErrorListItemApi> | null,
                detail: ReadFor<ErrorGroupDetailApi> | null
            ): string | null => rowWithKey(openKey, [detail?.value.item, seed?.item])?.message ?? null,
        ],
        tracesRequest: [
            (s) => [s.openMessage, s.readParams],
            (openMessage: string | null, readParams: DiagnosticsDrawerParams): ErrorTracesRequest | null =>
                openMessage ? { message: openMessage, params: readParams } : null,
        ],
        // The detail carries no New, so the drawer takes it from the first seen the list reads.
        isNew: [
            (s) => [s.openKey, s.firstSeen],
            (openKey: string | null, firstSeen: CellLoads<ErrorFirstSeen>): boolean =>
                openKey !== null && isNewError(firstSeen.get(openKey)),
        ],
        openDetail: [
            (s) => [s.detail, s.request],
            (detail: ReadFor<ErrorGroupDetailApi> | null, request: EntityRequest | null): ErrorGroupDetailApi | null =>
                valueFor(detail, request),
        ],
        item: [
            (s) => [s.openDetail, s.seed, s.request, s.detailFailure],
            (
                openDetail: ErrorGroupDetailApi | null,
                seed: EntitySeed<ErrorListItemApi> | null,
                request: EntityRequest | null,
                detailFailure: LoadFailure | null
            ): ErrorListItemApi | null => shownItem(openDetail?.item ?? null, seed, request, detailFailure),
        ],
        detailLoad: [
            (s) => [s.openDetail, s.detailFailure],
            (openDetail: ErrorGroupDetailApi | null, detailFailure: LoadFailure | null): ErrorDetailLoad =>
                detailLoadOf(openDetail, detailFailure),
        ],
        openRecentTraces: [
            (s) => [s.recentTraces, s.tracesRequest],
            (
                recentTraces: ReadFor<TraceListItemApi[]> | null,
                tracesRequest: ErrorTracesRequest | null
            ): TraceListItemApi[] | null => valueFor(recentTraces, tracesRequest),
        ],
        recentTracesLoad: [
            (s) => [s.openRecentTraces, s.recentTracesFailed, s.openMessage, s.detailFailure],
            (
                openRecentTraces: TraceListItemApi[] | null,
                recentTracesFailed: boolean,
                openMessage: string | null,
                detailFailure: LoadFailure | null
            ): TraceCellLoad<TraceListItemApi[]> =>
                recentTracesLoadOf(openRecentTraces, recentTracesFailed, openMessage !== null, detailFailure),
        ],
        recentTraceRows: [
            (s) => [s.openRecentTraces],
            (openRecentTraces: TraceListItemApi[] | null): TraceListRow[] => (openRecentTraces ?? []).map(traceRowOf),
        ],
        viewAllHref: [
            (s) => [s.openMessage, router.selectors.location, router.selectors.searchParams],
            (
                openMessage: string | null,
                location: { pathname: string; search: string },
                searchParams: Record<string, unknown>
            ): string | null =>
                openMessage ? scopedTracesHref(location, searchParams, { kind: 'error', value: openMessage }) : null,
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const readPreviews = createPreviewReader(cache, actions)
        return {
            openError: ({ item }) => {
                if (item.key === values.openKey) {
                    return
                }
                actions.setSeed({ item, params: values.readParams })
                diagnosticsTracking.entityOpened({ kind: 'error', trigger: 'row' })
                router.actions.push(
                    ...currentUrlWith(router.values, { ...CLOSED_TRACE_DRAWER, [ERROR_PARAM]: item.key })
                )
            },
            close: () => {
                router.actions.push(...currentUrlWith(router.values, { [ERROR_PARAM]: undefined }))
            },
            retry: async () => {
                const { request, tracesRequest, detailFailure, recentTracesFailed, openRecentTraces, previews } = values
                if (request && detailFailure === 'failed') {
                    actions.loadErrorDetail(request)
                }
                if (tracesRequest && recentTracesFailed) {
                    actions.loadErrorRecentTraces(tracesRequest)
                }
                if (openRecentTraces) {
                    await readPreviews(openRecentTraces, previews)
                }
            },
            loadErrorDetailFailure: ({ errorObject }) => {
                if (isReportedFailure(errorObject)) {
                    diagnosticsTracking.readFailed({ kind: 'error', read: 'detail' })
                }
            },
            loadErrorRecentTracesFailure: ({ errorObject }) => {
                if (isReportedFailure(errorObject)) {
                    diagnosticsTracking.readFailed({ kind: 'error', read: 'recent_traces' })
                }
            },
            loadErrorRecentTracesSuccess: ({ recentTraces }) => readPreviews(recentTraces.value, values.previews),
        }
    }),
    // Each fires on mount with the URL's error, then each time the open error or its selection changes, the traces once
    // the error's message is known. A trace opened over the drawer changes neither, so the drawer keeps what it read.
    subscriptions(({ actions, values, cache }) => ({
        request: (request: EntityRequest | null, previous: EntityRequest | null | undefined) => {
            if (!request) {
                cache.disposables.dispose(DETAIL_READ)
                return
            }
            if (previous && objectsEqual(request, previous)) {
                return
            }
            if (request.key !== previous?.key && values.seed?.item.key !== request.key) {
                diagnosticsTracking.entityOpened({ kind: 'error', trigger: 'url' })
            }
            actions.loadErrorDetail(request)
            actions.firstSeenWanted([request.key])
        },
        tracesRequest: (request: ErrorTracesRequest | null, previous: ErrorTracesRequest | null | undefined) => {
            if (!request) {
                cache.disposables.dispose(RECENT_TRACES_READ)
            } else if (!(previous && objectsEqual(request, previous))) {
                actions.loadErrorRecentTraces(request)
            }
        },
    })),
])
