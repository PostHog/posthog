export const ERRORS_LIST_FILTERS: ListFiltersLogicProps = {
    listId: 'errors',
    path: urls.aiObservabilityErrors(),
    searchParam: ERRORS_SEARCH_PARAM,
}

export type ErrorsSelectionParams = Omit<AiObservabilityErrorsListParams, 'limit' | 'offset'>

export type ErrorsPageRequest = DiagnosticsPageRequest<AiObservabilityErrorsListParams>

export type ShownPage = ShownDiagnosticsPage<ErrorListApi, AiObservabilityErrorsListParams>

function isErrorsPath(pathname: string): boolean {
    return removeProjectIdIfPresent(pathname) === ERRORS_LIST_FILTERS.path
}

function urlOrder(search: string): AiObservabilityErrorsListOrder | null {
    return enumValue(AiObservabilityErrorsListOrder, rawSearchParam(search, LIST_ORDER_PARAM))
}

