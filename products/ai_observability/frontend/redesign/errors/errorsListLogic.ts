export const errorsListLogic = kea<errorsListLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'errors', 'errorsListLogic']),
    connect(() => ({
        values: [
            listFiltersLogic(ERRORS_LIST_FILTERS),
            ['filters'],
            shellScopeLogic,
            ['dateFrom', 'dateTo', 'filterTestAccounts'],
        ],
    })),
    actions({
        selectionChanged: true,
        reload: true,
        setOrder: (order: AiObservabilityErrorsListOrder | null) => ({ order }),
        setPageIndex: (pageIndex: number) => ({ pageIndex }),
    }),
    loaders(({ cache }) => ({
        page: [
            null as ErrorListApi | null,
            {
                loadErrorsPage: async (request: ErrorsPageRequest, breakpoint): Promise<ErrorListApi> =>
                    readAbortablePage(
                        cache,
                        (signal) =>
                            aiObservabilityErrorsList(String(ApiConfig.getCurrentProjectId()), request.params, {
                                signal,
                            }),
                        breakpoint
                    ),
            },
        ],
    })),
    reducers({
        order: [null as AiObservabilityErrorsListOrder | null, { setOrder: (_, { order }) => order }],
        // Kept while the next page loads, so the sorted column does not blink off on each selection change.
        appliedOrder: [
            null as AiObservabilityErrorsListOrder | null,
            { loadErrorsPageSuccess: (current, { page }) => page?.order ?? current },
        ],
        // Kept while another page loads, so a page that fails to load leaves the pager where the rows are.
        shown: [
            null as ShownPage | null,
            {
                selectionChanged: () => null,
                loadErrorsPageSuccess: (current, { page, payload }) => (payload ? { page, request: payload } : current),
            },
        ],
        pageError: [
            null as unknown,
            {
                loadErrorsPage: () => null,
                loadErrorsPageFailure: (_, { errorObject }) => errorObject ?? true,
            },
        ],
    }),
    selectors({
        selectionParams: [
            (s) => [s.filters, s.dateFrom, s.dateTo, s.filterTestAccounts, s.order],
            (
                filters: ListFilters,
                dateFrom: string,
                dateTo: string | null,
                filterTestAccounts: boolean,
                order: AiObservabilityErrorsListOrder | null
            ): ErrorsSelectionParams =>
                diagnosticsListParams(
                    filters,
                    { dateFrom, dateTo, filterTestAccounts },
                    AiObservabilityErrorsListView,
                    order
                ),
        ],
        sortedBy: [
            (s) => [s.order, s.appliedOrder],
            (
                order: AiObservabilityErrorsListOrder | null,
                appliedOrder: AiObservabilityErrorsListOrder | null
            ): AiObservabilityErrorsListOrder | null => order ?? appliedOrder,
        ],
        pageIndex: [(s) => [s.shown], (shown: ShownPage | null): number => shown?.request.pageIndex ?? 0],
        items: [(s) => [s.shown], (shown: ShownPage | null): ErrorListItemApi[] => shown?.page.results ?? []],
        counts: [(s) => [s.shown], (shown: ShownPage | null): ErrorListCountsApi | null => shown?.page.counts ?? null],
        count: [(s) => [s.shown], (shown: ShownPage | null): number => shown?.page.count ?? 0],
        nothingCaptured: [(s) => [s.shown], (shown: ShownPage | null): boolean => !!shown?.page.nothingCaptured],
        refreshing: [
            (s) => [s.pageLoading, s.shown],
            (pageLoading: boolean, shown: ShownPage | null): boolean => pageLoading && shown !== null,
        ],
        canShowPrevious: [
            (s) => [s.pageIndex, s.pageLoading],
            (pageIndex: number, pageLoading: boolean): boolean => pageIndex > 0 && !pageLoading,
        ],
        canShowNext: [
            (s) => [s.pageIndex, s.count, s.pageLoading],
            (pageIndex: number, count: number, pageLoading: boolean): boolean =>
                pageIndex + 1 < pageCount(count, DIAGNOSTICS_PAGE_SIZE) && !pageLoading,
        ],
        rangeTooLongDetail: [
            (s) => [s.pageError],
            (pageError: unknown): string | null => rangeTooLongDetail(pageError),
        ],
        state: [
            (s) => [s.shown, s.pageError],
            (shown: ShownPage | null, pageError: unknown): ListTableState => diagnosticsListState(shown, pageError),
        ],
    }),
    listeners(({ actions, values }) => {
        const loadPage = (pageIndex: number): void => {
            actions.loadErrorsPage({
                pageIndex,
                params: { ...values.selectionParams, ...pageParams(pageIndex, DIAGNOSTICS_PAGE_SIZE) },
            })
        }
        return {
            selectionChanged: () => loadPage(0),
            setPageIndex: ({ pageIndex }) => loadPage(pageIndex),
            reload: () => loadPage(values.pageIndex),
            setOrder: ({ order }) => {
                const { location } = router.values
                if (order !== null && isErrorsPath(location.pathname) && urlOrder(location.search) !== order) {
                    router.actions.replace(...currentUrlWith(router.values, { [LIST_ORDER_PARAM]: order }))
                }
            },
            loadErrorsPageFailure: ({ errorObject }) => {
                if (rangeTooLongDetail(errorObject) === null) {
                    diagnosticsTracking.readFailed({ kind: 'error', read: 'list' })
                }
                // With no rows on screen the list shows the error itself.
                if (values.shown) {
                    lemonToast.error("Couldn't load errors. Try again.")
                }
            },
        }
    }),
    // Before the subscription, so the order in the URL is set when the list first reads.
    urlToAction(({ actions, values }) => ({
        [ERRORS_LIST_FILTERS.path]: (_, __, ___, { search }) => {
            const order = urlOrder(search)
            if (order !== values.order) {
                actions.setOrder(order)
            }
        },
    })),
    // Fires on mount with the settled filters, range and order, then on each change that must read page one again.
    subscriptions(({ actions }) => ({
        selectionParams: (next: ErrorsSelectionParams, previous: ErrorsSelectionParams | undefined) => {
            if (!previous || !objectsEqual(next, previous)) {
                actions.selectionChanged()
            }
        },
    })),
])
