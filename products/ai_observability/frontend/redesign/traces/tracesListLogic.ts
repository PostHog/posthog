export const tracesListLogic = kea<tracesListLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'traces', 'tracesListLogic']),
    connect(() => ({
        values: [
            listFiltersLogic(TRACES_LIST_FILTERS),
            ['filters'],
            shellScopeLogic,
            ['dateFrom', 'dateTo', 'filterTestAccounts'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [listFiltersLogic(TRACES_LIST_FILTERS), ['resetFilters'], shellScopeLogic, ['setFilterTestAccounts']],
    })),
    actions({
        clearFilters: true,
        selectionChanged: true,
        reload: true,
        showPreviousPage: true,
        showNextPage: true,
        setPageIndex: (pageIndex: number) => ({ pageIndex }),
    }),
    loaders(({ cache }) => ({
        page: [
            null as TraceListApi | null,
            {
                loadTracesPage: async (params: AiObservabilityTracesListParams, breakpoint): Promise<TraceListApi> => {
                    cache.pageRequestedAt = performance.now()
                    return readAbortablePage(
                        cache,
                        (signal) =>
                            aiObservabilityTracesList(String(ApiConfig.getCurrentProjectId()), params, { signal }),
                        breakpoint
                    )
                },
            },
        ],
    })),
    reducers({
        pages: [
            [] as TraceListApi[],
            {
                selectionChanged: () => [],
                loadTracesPageSuccess: (pages, { page, payload }) => appendedPages(pages, page, payload),
            },
        ],
        pageIndex: [
            0,
            {
                selectionChanged: () => 0,
                setPageIndex: (_, { pageIndex }) => pageIndex,
                loadTracesPageSuccess: (pageIndex, { payload }) => pageIndexAfterLoad(pageIndex, payload),
            },
        ],
        pagesParams: [
            null as AiObservabilityTracesListParams | null,
            {
                selectionChanged: () => null,
                loadTracesPageSuccess: (current, { payload }) => firstPageParams(current, payload),
            },
        ],
        pageFailed: [
            false,
            {
                loadTracesPage: () => false,
                loadTracesPageFailure: () => true,
            },
        ],
    }),
    selectors({
        searchEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.LLM_OBSERVABILITY_TRACE_SEARCH],
        ],
        requestParams: [
            (s) => [s.filters, s.dateFrom, s.dateTo, s.filterTestAccounts, s.searchEnabled],
            (
                filters: ListFilters,
                dateFrom: string,
                dateTo: string | null,
                filterTestAccounts: boolean,
                searchEnabled: boolean
            ): AiObservabilityTracesListParams => ({
                ...listRequestParams(filters, { dateFrom, dateTo, filterTestAccounts, searchEnabled }),
                view: toView(filters.quickFilter),
                limit: TRACES_PAGE_SIZE,
            }),
        ],
        shownPage: [
            (s) => [s.pages, s.pageIndex],
            (pages: TraceListApi[], pageIndex: number): TraceListApi | null => shownPageOf(pages, pageIndex),
        ],
        items: [(s) => [s.shownPage], (shownPage: TraceListApi | null): TraceListItemApi[] => itemsOf(shownPage)],
        counts: [(s) => [s.pages], (pages: TraceListApi[]): TraceListCountsApi | null => pages[0]?.counts ?? null],
        canShowPrevious: [
            (s) => [s.pageIndex, s.pageLoading],
            (pageIndex: number, pageLoading: boolean): boolean => canStepBack(pageIndex, pageLoading),
        ],
        canShowNext: [(s) => [s.shownPage], (shownPage: TraceListApi | null): boolean => canStepForward(shownPage)],
        refreshing: [
            (s) => [s.pageLoading, s.pages],
            (pageLoading: boolean, pages: TraceListApi[]): boolean => isRefreshing(pageLoading, pages),
        ],
        state: [
            (s) => [s.pages, s.pageFailed, s.pagesParams],
            (
                pages: TraceListApi[],
                pageFailed: boolean,
                pagesParams: AiObservabilityTracesListParams | null
            ): ListTableState => listStateOf(pages, pageFailed, pagesParams, narrowsSelection),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        clearFilters: () => {
            // Clearing turns test account filtering off, because with no choice the project's default applies, and
            // that default may hide test accounts.
            actions.setFilterTestAccounts(false)
            actions.resetFilters()
        },
        selectionChanged: () => actions.loadTracesPage(values.requestParams),
        reload: () => actions.loadTracesPage(values.requestParams),
        showPreviousPage: () => {
            if (values.canShowPrevious) {
                actions.setPageIndex(values.pageIndex - 1)
            }
        },
        showNextPage: () => {
            const step = nextPageStep(values)
            if (step && 'show' in step) {
                actions.setPageIndex(step.show)
            } else if (step) {
                actions.loadTracesPage(step.load)
            }
        },
        loadTracesPageSuccess: ({ page, payload }) => {
            if (!payload || payload.cursor) {
                return
            }
            tracesListTracking.listLoaded({
                rowsWaitMs: Math.round(performance.now() - cache.pageRequestedAt),
                rowCount: page.items.length,
                dateFrom: payload.date_from ?? null,
                quickFilter: payload.view ?? null,
                searched: !!payload.search,
            })
        },
        loadTracesPageFailure: () => {
            // With no rows on screen the list shows the error itself.
            if (values.pages.length > 0) {
                lemonToast.error("Couldn't load traces. Try again.")
            }
        },
    })),
    // Fires on mount with the settled filters and range, then on each change that must reload the list.
    subscriptions(({ actions }) => ({
        requestParams: () => actions.selectionChanged(),
    })),
])
