export const TRACES_PAGE_SIZE = 50

export const TRACES_LIST_FILTERS: ListFiltersLogicProps = { listId: 'traces', path: urls.aiObservabilityTraces() }

function toView(quickFilter: string | null): AiObservabilityTracesListView | undefined {
    return Object.values(AiObservabilityTracesListView).find((view) => view === quickFilter)
}

function narrowsSelection(params: AiObservabilityTracesListParams | null): boolean {
    return !!(params?.properties || params?.search || params?.view || params?.filter_test_accounts)
}

