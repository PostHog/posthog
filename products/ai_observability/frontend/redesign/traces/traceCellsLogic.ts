import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { ApiConfig } from 'lib/api'

import {
    aiObservabilityTracesPeopleCreate,
    aiObservabilityTracesPreviewsCreate,
    aiObservabilityTracesSentimentCreate,
} from '../../generated/api'
import type {
    TraceListItemApi,
    TracePersonApi,
    TracePersonItemApi,
    TracePreviewApi,
    TraceSentimentApi,
    TraceSentimentItemApi,
} from '../../generated/api.schemas'
import type { AiObservabilityTracesListParams, TraceListApi } from '../../generated/api.schemas'
import { rowsToRead, withFailed, withLoaded, withRequested } from '../shared/cellLoads'
import type { TraceCellLoad } from '../shared/cellLoads'
import { createCellReader } from '../shared/cellReader'
import { pageRequest } from '../shared/pageRequest'
import { noEntries } from '../shared/readOrFailure'
import { tracesListLogic } from './tracesListLogic'
import { tracesListTracking } from './tracesListTracking'

export type TraceCellRead = 'previews' | 'people' | 'sentiment'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceCellsLogicValues {
    items: TraceListItemApi[] // tracesListLogic
    people: ReadonlyMap<string, TraceCellLoad<TracePersonApi | null>>
    previews: ReadonlyMap<string, TraceCellLoad<TracePreviewApi>>
    sentiments: ReadonlyMap<string, TraceCellLoad<TraceSentimentApi | null>>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceCellsLogicActions {
    loadTracesPageFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    } // tracesListLogic
    loadTracesPageSuccess: (
        page: TraceListApi,
        payload?: AiObservabilityTracesListParams | undefined
    ) => {
        page: TraceListApi
        payload?: AiObservabilityTracesListParams
    } // tracesListLogic
    reload: () => {
        value: true
    } // tracesListLogic
    setPageIndex: (pageIndex: number) => {
        pageIndex: number
    } // tracesListLogic
    cellsFailed: (
        read: TraceCellRead,
        traceIds: string[]
    ) => {
        read: TraceCellRead
        traceIds: string[]
    }
    cellsRequested: (
        read: TraceCellRead,
        traceIds: string[]
    ) => {
        read: TraceCellRead
        traceIds: string[]
    }
    peopleLoaded: (items: TracePersonItemApi[]) => {
        items: TracePersonItemApi[]
    }
    previewsLoaded: (items: TracePreviewApi[]) => {
        items: TracePreviewApi[]
    }
    sentimentsLoaded: (items: TraceSentimentItemApi[]) => {
        items: TraceSentimentItemApi[]
    }
}

export type traceCellsLogicType = MakeLogicType<traceCellsLogicValues, traceCellsLogicActions>

export const traceCellsLogic = kea<traceCellsLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'traces', 'traceCellsLogic']),
    connect(() => ({
        values: [tracesListLogic, ['items']],
        actions: [tracesListLogic, ['loadTracesPageSuccess', 'loadTracesPageFailure', 'setPageIndex', 'reload']],
    })),
    actions({
        cellsRequested: (read: TraceCellRead, traceIds: string[]) => ({ read, traceIds }),
        cellsFailed: (read: TraceCellRead, traceIds: string[]) => ({ read, traceIds }),
        previewsLoaded: (items: TracePreviewApi[]) => ({ items }),
        peopleLoaded: (items: TracePersonItemApi[]) => ({ items }),
        sentimentsLoaded: (items: TraceSentimentItemApi[]) => ({ items }),
    }),
    reducers({
        previews: [
            noEntries<TraceCellLoad<TracePreviewApi>>(),
            {
                cellsRequested: (state, { read, traceIds }) =>
                    read === 'previews' ? withRequested(state, traceIds) : state,
                cellsFailed: (state, { read, traceIds }) => (read === 'previews' ? withFailed(state, traceIds) : state),
                previewsLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.traceId, item])
                    ),
            },
        ],
        people: [
            noEntries<TraceCellLoad<TracePersonApi | null>>(),
            {
                cellsRequested: (state, { read, traceIds }) =>
                    read === 'people' ? withRequested(state, traceIds) : state,
                cellsFailed: (state, { read, traceIds }) => (read === 'people' ? withFailed(state, traceIds) : state),
                peopleLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.traceId, item.person])
                    ),
            },
        ],
        sentiments: [
            noEntries<TraceCellLoad<TraceSentimentApi | null>>(),
            {
                cellsRequested: (state, { read, traceIds }) =>
                    read === 'sentiment' ? withRequested(state, traceIds) : state,
                cellsFailed: (state, { read, traceIds }) =>
                    read === 'sentiment' ? withFailed(state, traceIds) : state,
                sentimentsLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.traceId, item.sentiment])
                    ),
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const readCells = createCellReader<TraceListItemApi, TraceCellRead, { traceId: string }>({
            cache,
            idOf: (row) => row.id,
            itemIdOf: (item) => item.traceId,
            requested: actions.cellsRequested,
            failed: actions.cellsFailed,
        })

        const readShownPage = async (refresh: boolean): Promise<void> => {
            const projectId = String(ApiConfig.getCurrentProjectId())
            const previewsRequestedAt = performance.now()
            await Promise.all([
                readCells(
                    'previews',
                    rowsToRead(values.items, values.previews, refresh),
                    (rows) => aiObservabilityTracesPreviewsCreate(projectId, { trace_ids: rows.map((row) => row.id) }),
                    (items) => {
                        actions.previewsLoaded(items)
                        tracesListTracking.cellsLoaded({
                            previewsWaitMs: Math.round(performance.now() - previewsRequestedAt),
                            rowCount: items.length,
                        })
                    }
                ),
                readCells(
                    'people',
                    rowsToRead(values.items, values.people, refresh),
                    (rows) => aiObservabilityTracesPeopleCreate(projectId, pageRequest(rows)),
                    (items) => actions.peopleLoaded(items)
                ),
                readCells(
                    'sentiment',
                    rowsToRead(values.items, values.sentiments, refresh),
                    (rows) => aiObservabilityTracesSentimentCreate(projectId, pageRequest(rows)),
                    (items) => actions.sentimentsLoaded(items)
                ),
            ])
        }

        return {
            // A reload shows the first page again once it lands, and its cells are read again with it.
            reload: () => {
                cache.refreshOnNextPage = true
            },
            loadTracesPageFailure: () => {
                cache.refreshOnNextPage = false
            },
            loadTracesPageSuccess: async () => {
                const refresh = !!cache.refreshOnNextPage
                cache.refreshOnNextPage = false
                await readShownPage(refresh)
            },
            setPageIndex: () => readShownPage(false),
        }
    }),
])
