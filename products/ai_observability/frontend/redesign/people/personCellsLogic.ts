import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { ApiConfig } from 'lib/api'

import { aiObservabilityPeopleFirstSeenCreate } from '../../generated/api'
import type {
    AiObservabilityPeopleListParams,
    PeopleFirstSeenRequestApi,
    PersonListApi,
} from '../../generated/api.schemas'
import { TraceCellLoad, withFailed, withLoaded, withRequested } from '../shared/cellLoads'
import { CellEntry, createPageCellReader } from '../shared/pageCellReader'
import { noEntries } from '../shared/readOrFailure'
import { peopleListLogic } from './peopleListLogic'
import type { PersonFirstSeen } from './types'

type FirstSeenRange = Omit<PeopleFirstSeenRequestApi, 'person_ids'>

// First seen depends on the range and the test account switch only, so the list's other params never ask again.
function firstSeenRange(params: AiObservabilityPeopleListParams | undefined): FirstSeenRange {
    return {
        date_from: params?.date_from,
        date_to: params?.date_to,
        filter_test_accounts: params?.filter_test_accounts,
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface personCellsLogicValues {
    firstSeen: ReadonlyMap<string, TraceCellLoad<PersonFirstSeen>>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface personCellsLogicActions {
    loadPeoplePageFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    } // peopleListLogic
    loadPeoplePageSuccess: (
        page: PersonListApi,
        payload?: AiObservabilityPeopleListParams | undefined
    ) => {
        page: PersonListApi
        payload?: AiObservabilityPeopleListParams
    } // peopleListLogic
    reload: () => {
        value: true
    } // peopleListLogic
    firstSeenFailed: (keys: string[]) => {
        keys: string[]
    }
    firstSeenLoaded: (entries: CellEntry<PersonFirstSeen>[]) => {
        entries: CellEntry<PersonFirstSeen>[]
    }
    firstSeenParamsChanged: () => {
        value: true
    }
    firstSeenRequested: (keys: string[]) => {
        keys: string[]
    }
}

export type personCellsLogicType = MakeLogicType<personCellsLogicValues, personCellsLogicActions>

/** When each person on the people list was first seen, keyed by person id. */
export const personCellsLogic = kea<personCellsLogicType>([
    path(['products', 'ai_observability', 'frontend', 'redesign', 'people', 'personCellsLogic']),
    connect(() => ({
        actions: [peopleListLogic, ['loadPeoplePageSuccess', 'loadPeoplePageFailure', 'reload']],
    })),
    actions({
        firstSeenParamsChanged: true,
        firstSeenRequested: (keys: string[]) => ({ keys }),
        firstSeenFailed: (keys: string[]) => ({ keys }),
        firstSeenLoaded: (entries: CellEntry<PersonFirstSeen>[]) => ({ entries }),
    }),
    reducers({
        firstSeen: [
            noEntries<TraceCellLoad<PersonFirstSeen>>(),
            {
                firstSeenParamsChanged: () => noEntries<TraceCellLoad<PersonFirstSeen>>(),
                firstSeenRequested: (state, { keys }) => withRequested(state, keys),
                firstSeenFailed: (state, { keys }) => withFailed(state, keys),
                firstSeenLoaded: (state, { entries }) => withLoaded(state, entries),
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const reader = createPageCellReader<FirstSeenRange, PersonFirstSeen>({
            cache,
            loads: () => values.firstSeen,
            paramsChanged: actions.firstSeenParamsChanged,
            requested: actions.firstSeenRequested,
            failed: actions.firstSeenFailed,
            loaded: actions.firstSeenLoaded,
            request: async (personIds, range) => {
                const { items, checkedFrom } = await aiObservabilityPeopleFirstSeenCreate(
                    String(ApiConfig.getCurrentProjectId()),
                    { ...range, person_ids: personIds }
                )
                return items.map(({ personId, firstSeen, isNew }) => [personId, { firstSeen, checkedFrom, isNew }])
            },
        })
        return {
            // A reload shows the page again once it lands, and its first seen is read again with it.
            reload: reader.pageReloading,
            loadPeoplePageFailure: reader.pageFailed,
            loadPeoplePageSuccess: async ({ page, payload }) => {
                await reader.pageLoaded(
                    page.results.map((person) => person.id),
                    firstSeenRange(payload)
                )
            },
        }
    }),
])
