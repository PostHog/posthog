const LOADING = { status: 'loading' } as const
const FAILED = { status: 'error' } as const

function projectId(): string {
    return String(ApiConfig.getCurrentProjectId())
}

function toTraceRow(item: TraceListItemApi): TraceListRow {
    return {
        traceId: item.id,
        timestamp: item.createdAt,
        stepId: null,
        overview: item,
        defaultStepId: item.defaultNodeId ?? undefined,
    }
}

function failAll<T>(loads: CellLoads<T>): CellLoads<T> {
    return withFailed(loads, [...loads.keys()])
}

