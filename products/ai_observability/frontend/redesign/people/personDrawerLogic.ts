export const personDrawerLogic = kea<personDrawerLogicType>([
    props({} as PersonDrawerLogicProps),
    key((props) => props.personId),
    path((key) => ['products', 'ai_observability', 'frontend', 'redesign', 'people', 'personDrawerLogic', key]),
    connect(() => ({
        values: [
            peopleListLogic,
            ['items', 'state as listState', 'filters as listFilters'],
            personCellsLogic,
            ['firstSeen as firstSeenLoads'],
            shellScopeLogic,
            ['dateFrom', 'dateTo', 'filterTestAccounts'],
            traceDrawerLogic({ listId: PERSON_TRACES_LIST }),
            ['openTraceId'],
        ],
        actions: [peopleListLogic, ['openPerson']],
    })),
    actions({
        scopeChanged: true,
        personListed: (person: PersonListItemApi) => ({ person }),
        loadPerson: true,
        personLookedUp: (person: PersonListItemApi | null) => ({ person }),
        personLookUpFailed: true,
        loadRecentTraces: true,
        recentTracesLoaded: (traces: TraceListItemApi[]) => ({ traces }),
        recentTracesFailed: true,
        traceTitlesLoaded: (items: TracePreviewApi[]) => ({ items }),
        traceTitlesFailed: true,
        loadRecentSessions: true,
        recentSessionsLoaded: (sessions: SessionListItemApi[]) => ({ sessions }),
        recentSessionsFailed: true,
        sessionTitlesLoaded: (items: SessionPreviewApi[]) => ({ items }),
        sessionTitlesFailed: true,
        close: true,
    }),
    reducers({
        // The person's row in the range, from the list or a read of the person. The drawer keeps it while the list pages,
        // sorts, searches or hides anonymous people, since those change what the list shows, not who the person is.
        keptPerson: [
            null as PersonListItemApi | null,
            {
                scopeChanged: () => null,
                personListed: (_, { person }) => person,
                personLookedUp: (_, { person }) => person,
            },
        ],
        // Null until the person is read, which happens only when the loaded page does not hold them.
        lookedUp: [
            null as TraceCellLoad<PersonListItemApi | null> | null,
            {
                scopeChanged: () => null,
                loadPerson: () => LOADING,
                personLookedUp: (_, { person }) => ({ status: 'ready', value: person }),
                personLookUpFailed: () => FAILED,
            },
        ],
        recentTraces: [
            LOADING as TraceCellLoad<TraceListItemApi[]>,
            {
                loadRecentTraces: () => LOADING,
                recentTracesLoaded: (_, { traces }) => ({ status: 'ready', value: traces }),
                recentTracesFailed: () => FAILED,
            },
        ],
        traceTitles: [
            noEntries<TraceCellLoad<TracePreviewApi>>(),
            {
                recentTracesLoaded: (_, { traces }) =>
                    withRequested(
                        noEntries(),
                        traces.map((trace) => trace.id)
                    ),
                traceTitlesLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.traceId, item])
                    ),
                traceTitlesFailed: (state) => failAll(state),
            },
        ],
        recentSessions: [
            LOADING as TraceCellLoad<SessionListItemApi[]>,
            {
                loadRecentSessions: () => LOADING,
                recentSessionsLoaded: (_, { sessions }) => ({ status: 'ready', value: sessions }),
                recentSessionsFailed: () => FAILED,
            },
        ],
        sessionTitles: [
            noEntries<TraceCellLoad<SessionPreviewApi>>(),
            {
                recentSessionsLoaded: (_, { sessions }) =>
                    withRequested(
                        noEntries(),
                        sessions.map((session) => session.id)
                    ),
                sessionTitlesLoaded: (state, { items }) =>
                    withLoaded(
                        state,
                        items.map((item) => [item.sessionId, item])
                    ),
                sessionTitlesFailed: (state) => failAll(state),
            },
        ],
    }),
    selectors({
        range: [
            (s) => [s.dateFrom, s.dateTo, s.filterTestAccounts],
            (dateFrom: string, dateTo: string | null, filterTestAccounts: boolean): PersonRange =>
                personRange(dateFrom, dateTo, filterTestAccounts),
            { resultEqualityCheck: objectsEqual },
        ],
        propertyFilters: [
            (s) => [s.listFilters],
            (listFilters: ListFilters): AnyPropertyFilter[] => listFilters.propertyFilters,
        ],
        // The person's row and sections follow the list's range and property filters, not its search or New view.
        scope: [
            (s) => [s.range, s.propertyFilters],
            (range: PersonRange, propertyFilters: AnyPropertyFilter[]): PersonRange => ({
                ...range,
                properties: propertyFilters.length > 0 ? JSON.stringify(propertyFilters) : undefined,
            }),
            { resultEqualityCheck: objectsEqual },
        ],
        listedPerson: [
            (s, p) => [s.items, p.personId],
            (items: PersonListItemApi[], personId: string): PersonListItemApi | null =>
                items.find((item) => item.id === personId) ?? null,
        ],
        person: [
            (s) => [s.listedPerson, s.keptPerson],
            (listedPerson: PersonListItemApi | null, keptPerson: PersonListItemApi | null): PersonListItemApi | null =>
                listedPerson ?? keptPerson,
        ],
        // The list answers first, so the person is read only once a loaded page, or a failed one, leaves them out.
        needsLookUp: [
            (s) => [s.person, s.lookedUp, s.listState],
            (
                person: PersonListItemApi | null,
                lookedUp: TraceCellLoad<PersonListItemApi | null> | null,
                listState: ListTableState
            ): boolean => person === null && lookedUp === null && listState !== 'loading',
        ],
        status: [
            (s) => [s.person, s.lookedUp],
            (
                person: PersonListItemApi | null,
                lookedUp: TraceCellLoad<PersonListItemApi | null> | null
            ): PersonDrawerStatus => {
                if (person) {
                    return 'ready'
                }
                if (lookedUp?.status === 'ready') {
                    return lookedUp.value ? 'ready' : 'not_found'
                }
                return lookedUp?.status === 'error' ? 'error' : 'loading'
            },
        ],
        firstSeen: [
            (s, p) => [s.firstSeenLoads, p.personId],
            (loads: CellLoads<PersonFirstSeen>, personId: string): TraceCellLoad<PersonFirstSeen> | null =>
                loads.get(personId) ?? null,
        ],
        // The list reads the first seen of the people on its page, and the drawer reads it for anyone else.
        firstSeenMissing: [
            (s) => [s.listedPerson, s.person, s.firstSeen],
            (
                listedPerson: PersonListItemApi | null,
                person: PersonListItemApi | null,
                firstSeen: TraceCellLoad<PersonFirstSeen> | null
            ): boolean => !listedPerson && !!person && firstSeen === null,
        ],
        traceRows: [
            (s) => [s.recentTraces],
            (recentTraces: TraceCellLoad<TraceListItemApi[]>): TraceListRow[] =>
                recentTraces.status === 'ready' ? recentTraces.value.map(toTraceRow) : [],
        ],
        viewAllHref: [
            (s, p) => [s.range, s.propertyFilters, p.personId],
            (range: PersonRange, propertyFilters: AnyPropertyFilter[], personId: string): string =>
                shellHref(urls.aiObservabilityTraces(), {
                    ...range,
                    filters: propertyFilters.length > 0 ? propertyFilters : undefined,
                    person: personId,
                }),
        ],
        personHref: [
            (s) => [s.person],
            (person: PersonListItemApi | null): string | null =>
                person ? urls.personByDistinctId(person.person.distinctId) : null,
        ],
        sessionHref: [
            (s) => [s.range],
            (range: PersonRange): ((session: SessionListItemApi) => string) =>
                (session) =>
                    shellHref(urls.aiObservabilitySessions(), {
                        ...range,
                        [SESSION_PARAM]: session.id,
                        [SESSION_TIMESTAMP_PARAM]: session.firstSeen,
                    }),
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        const latestReads: Map<string, number> = (cache.latestReads ??= new Map())

        // A new scope reads every section again, so only the latest read of a section may settle it.
        const settle = async <T>(
            name: string,
            request: () => Promise<T>
        ): Promise<{ value: T } | { failure: LoadFailure } | null> => {
            const readId = (cache.lastReadId = (cache.lastReadId ?? 0) + 1)
            latestReads.set(name, readId)
            const result = await readOrFailure(request())
            return cache.disposables.isDisposed || latestReads.get(name) !== readId ? null : result
        }

        const failed = (section: PersonDrawerSection, fail: () => void): void => {
            fail()
            peopleTracking.drawerSectionFailed(section)
        }

        const scope = (): PersonRange & { person_id: string } => ({
            ...values.scope,
            person_id: props.personId,
        })

        return {
            loadPerson: async () => {
                const readScope = values.scope
                const result = await settle('person', () => readPerson(props.personId, readScope))
                // An older scope's answer can land while the list loads the new scope, before a newer read starts.
                if (!result || !objectsEqual(readScope, values.scope)) {
                    return
                }
                if ('value' in result) {
                    actions.personLookedUp(result.value)
                } else if (result.failure === 'not_found') {
                    actions.personLookedUp(null)
                } else {
                    failed('person', actions.personLookUpFailed)
                }
            },
            loadRecentTraces: async () => {
                const result = await settle('recent_traces', () =>
                    aiObservabilityTracesList(projectId(), { ...scope(), limit: RECENT_LIMIT })
                )
                if (!result) {
                    return
                }
                if ('failure' in result) {
                    failed('recent_traces', actions.recentTracesFailed)
                    return
                }
                const traces = result.value.items
                actions.recentTracesLoaded(traces)
                if (traces.length === 0) {
                    return
                }
                const titles = await settle('trace_titles', () =>
                    aiObservabilityTracesPreviewsCreate(projectId(), { trace_ids: traces.map((trace) => trace.id) })
                )
                if (titles && 'failure' in titles) {
                    actions.traceTitlesFailed()
                } else if (titles) {
                    actions.traceTitlesLoaded(titles.value.items)
                }
            },
            loadRecentSessions: async () => {
                const result = await settle('recent_sessions', () =>
                    aiObservabilitySessionsList(projectId(), { ...scope(), limit: RECENT_LIMIT })
                )
                if (!result) {
                    return
                }
                if ('failure' in result) {
                    failed('recent_sessions', actions.recentSessionsFailed)
                    return
                }
                const sessions = result.value.items
                actions.recentSessionsLoaded(sessions)
                if (sessions.length === 0) {
                    return
                }
                const titles = await settle('session_titles', () =>
                    aiObservabilitySessionsPreviewsCreate(projectId(), {
                        session_ids: sessions.map((session) => session.id),
                    })
                )
                if (titles && 'failure' in titles) {
                    actions.sessionTitlesFailed()
                } else if (titles) {
                    actions.sessionTitlesLoaded(titles.value.items)
                }
            },
            close: () => actions.openPerson(null),
        }
    }),
    // Each fires on mount, then on each change.
    subscriptions(({ actions, values, props }) => ({
        scope: () => {
            actions.scopeChanged()
            actions.loadRecentTraces()
            actions.loadRecentSessions()
        },
        listedPerson: (listedPerson: PersonListItemApi | null) => {
            if (listedPerson) {
                actions.personListed(listedPerson)
            }
        },
        needsLookUp: (needsLookUp: boolean) => {
            if (needsLookUp) {
                actions.loadPerson()
            }
        },
        firstSeenMissing: (missing: boolean) => {
            if (missing) {
                personCellsLogic.actions.readFirstSeen([props.personId], values.range)
            }
        },
    })),
    afterMount(({ actions, values, cache }) => {
        cache.disposables.add(() => {
            // Capture runs before the trace drawer's own listener, so one Escape closes the trace and leaves the person.
            const closeOnEscape = (event: KeyboardEvent): void => {
                if (values.openTraceId === null && shouldCloseOnEscape(event)) {
                    actions.close()
                }
            }
            document.addEventListener('keydown', closeOnEscape, true)
            return () => document.removeEventListener('keydown', closeOnEscape, true)
        })
    }),
])
