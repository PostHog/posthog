import { MakeLogicType, afterMount, connect, kea, listeners, path } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import * as api from '../generated/api'
import type { EvalSuggestionSettingsApi } from '../generated/api.schemas'

export const EVAL_SUGGESTIONS_SETTINGS_URL = urls.settings(
    'project-ai-observability',
    'ai-observability-eval-suggestions'
)

export type SuggestionsTurnOffReason = 'not_useful' | 'write_own_evals' | 'not_now'

export interface SuggestionsSwitchedProperties {
    source: 'evals_page' | 'settings'
    reason?: SuggestionsTurnOffReason | null
    open_cards?: number
}

// pinned: analytics event names and properties, renaming them breaks the suggestion experiment dashboards
export function captureSuggestionsSwitched(enabled: boolean, properties: SuggestionsSwitchedProperties): void {
    posthog.capture(enabled ? 'llma eval suggestions turned on' : 'llma eval suggestions turned off', properties)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface evalSuggestionsSettingsLogicValues {
    currentTeamId: number | null // teamLogic
    suggestionSettings: EvalSuggestionSettingsApi | null
    suggestionSettingsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface evalSuggestionsSettingsLogicActions {
    loadSuggestionSettings: () => any
    loadSuggestionSettingsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSuggestionSettingsSuccess: (
        suggestionSettings: EvalSuggestionSettingsApi,
        payload?: any
    ) => {
        suggestionSettings: EvalSuggestionSettingsApi
        payload?: any
    }
    setSuggestionsEnabled: (enabled: boolean) => boolean
    setSuggestionsEnabledFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    setSuggestionsEnabledSuccess: (
        suggestionSettings: EvalSuggestionSettingsApi,
        payload?: boolean
    ) => {
        suggestionSettings: EvalSuggestionSettingsApi
        payload?: boolean
    }
}

export type evalSuggestionsSettingsLogicType = MakeLogicType<
    evalSuggestionsSettingsLogicValues,
    evalSuggestionsSettingsLogicActions
>

export const evalSuggestionsSettingsLogic = kea<evalSuggestionsSettingsLogicType>([
    path(['products', 'ai_observability', 'settings', 'evalSuggestionsSettingsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    loaders(({ values }) => ({
        suggestionSettings: [
            null as EvalSuggestionSettingsApi | null,
            {
                loadSuggestionSettings: async () =>
                    await api.evaluationSuggestionsSettingsRetrieve(String(values.currentTeamId)),
                setSuggestionsEnabled: async (enabled: boolean) =>
                    await api.evaluationSuggestionsSettingsPartialUpdate(String(values.currentTeamId), { enabled }),
            },
        ],
    })),

    listeners(() => ({
        setSuggestionsEnabledSuccess: ({ suggestionSettings }) => {
            captureSuggestionsSwitched(suggestionSettings.enabled, { source: 'settings' })
        },
    })),

    afterMount(({ actions }) => {
        actions.loadSuggestionSettings()
    }),
])
