export type aiObservabilitySelfDrivingLogicType = MakeLogicType<
    aiObservabilitySelfDrivingLogicValues,
    aiObservabilitySelfDrivingLogicActions,
    Record<string, any>,
    aiObservabilitySelfDrivingLogicMeta
>

export const aiObservabilitySelfDrivingLogic = kea<aiObservabilitySelfDrivingLogicType>([
    path(['products', 'ai_observability', 'selfDriving', 'aiObservabilitySelfDrivingLogic']),

    connect(() => ({
        values: [signalSourcesLogic, ['sourceConfigs', 'sourceConfigsLoading']],
        actions: [signalSourcesLogic, ['loadSourceConfigs']],
    })),

    actions({
        setExpandedSections: (expandedSections: AIObservabilitySelfDrivingSection[]) => ({ expandedSections }),
        setOpenScoutTemplateKey: (openScoutTemplateKey: AIObservabilityScoutTemplateKey | null) => ({
            openScoutTemplateKey,
        }),
    }),

    loaders({
        anomalyAlertInvestigations: [
            null as AlertApi[] | null,
            {
                loadAnomalyAlertInvestigations: async () => {
                    const teamId = teamLogic.values.currentTeamId
                    return teamId ? await listAllAnomalyAlertInvestigations(teamId.toString()) : []
                },
            },
        ],
        evaluationReports: [
            null as EvaluationReportApi[] | null,
            {
                loadSelfDrivingEvaluationReports: async () => {
                    const teamId = teamLogic.values.currentTeamId
                    return teamId ? await listAllEvaluationReports(teamId.toString()) : []
                },
            },
        ],
    }),

    reducers({
        expandedSections: [
            DEFAULT_EXPANDED_SECTIONS,
            { persist: true },
            {
                setExpandedSections: (_, { expandedSections }) => expandedSections,
            },
        ],
        openScoutTemplateKey: [
            null as AIObservabilityScoutTemplateKey | null,
            {
                setOpenScoutTemplateKey: (_, { openScoutTemplateKey }) => openScoutTemplateKey,
            },
        ],
    }),

    selectors({
        evaluationReportsByEvaluationId: [
            (selectors) => [selectors.evaluationReports],
            (reports: EvaluationReportApi[] | null): Record<string, EvaluationReportApi> | null =>
                reports
                    ? Object.fromEntries(
                          reports.filter((report) => !report.deleted).map((report) => [report.evaluation, report])
                      )
                    : null,
        ],
    }),

    // `#template=<key>` opens that template's create modal, so a posthog.com pocket guide can hand
    // someone straight into it. The fragment is stripped on arrival: it carries no config of its
    // own (the template does), and leaving it in the URL would reopen the modal on every refresh.
    urlToAction(({ actions }) => ({
        [urls.aiObservabilitySelfDriving()]: (_, __, hashParams) => {
            if (hashParams?.['template'] === undefined) {
                return
            }
            const { template, ...remainingHashParams } = hashParams
            router.actions.replace(router.values.location.pathname, router.values.searchParams, remainingHashParams)
            const matched = findAIObservabilityScoutTemplate(template)
            if (matched) {
                actions.setOpenScoutTemplateKey(matched.key)
            } else {
                // The fragment is already stripped, so staying silent would leave the reader with
                // nothing to look at and nothing to report. `inboxSceneLogic` toasts here too.
                lemonToast.error("That link points to a scout template that doesn't exist. Pick one below.")
            }
        },
    })),

    afterMount(({ actions, values }) => {
        actions.loadAnomalyAlertInvestigations()
        actions.loadSelfDrivingEvaluationReports()
        // signalSourcesLogic only loads these behind the inbox's own flag, and the signal source
        // switches in this tab need the rows either way.
        if (values.sourceConfigs === null && !values.sourceConfigsLoading) {
            actions.loadSourceConfigs()
        }
    }),
])
