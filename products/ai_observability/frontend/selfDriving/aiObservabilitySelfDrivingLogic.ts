import { MakeLogicType, actions, afterMount, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import * as alertsApi from 'products/alerts/frontend/generated/api'
import type { AlertApi } from 'products/alerts/frontend/generated/api.schemas'

import { listAllEvaluationReports } from '../evaluations/evaluationsApi'
import type { EvaluationReportApi } from '../generated/api.schemas'
import { listAllPages } from '../listAllPages'
import { AI_OBSERVABILITY_SCOUT_TAG } from './aiObservabilityScoutTemplates'

const ANOMALY_ALERTS_PAGE_SIZE = 100

export const AI_OBSERVABILITY_SELF_DRIVING_SECTIONS = {
    SCOUTS: 'scouts',
    EVAL_REPORTS: 'eval-reports',
    ANOMALY_ALERT_INVESTIGATIONS: 'anomaly-alert-investigations',
} as const

export type AIObservabilitySelfDrivingSection =
    (typeof AI_OBSERVABILITY_SELF_DRIVING_SECTIONS)[keyof typeof AI_OBSERVABILITY_SELF_DRIVING_SECTIONS]

const DEFAULT_EXPANDED_SECTIONS: AIObservabilitySelfDrivingSection[] = [
    AI_OBSERVABILITY_SELF_DRIVING_SECTIONS.SCOUTS,
    AI_OBSERVABILITY_SELF_DRIVING_SECTIONS.EVAL_REPORTS,
    AI_OBSERVABILITY_SELF_DRIVING_SECTIONS.ANOMALY_ALERT_INVESTIGATIONS,
]

async function listAllAnomalyAlertInvestigations(projectId: string): Promise<AlertApi[]> {
    return listAllPages((offset) =>
        alertsApi.alertsList(projectId, {
            has_detector: true,
            insight_tag: AI_OBSERVABILITY_SCOUT_TAG,
            limit: ANOMALY_ALERTS_PAGE_SIZE,
            offset,
        })
    )
}

