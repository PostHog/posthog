/**
 * Owns the project's instrumentation checklist: the dashboard card, the tab empty-state
 * overrides and the trace-detail note all read their verdict from here.
 *
 * Every failure mode collapses to the same shape: `checklistCardState` sits at 'hidden' and
 * `warningForCheck` returns null, whether the flag is off, the request failed, or nothing has
 * loaded yet. A consumer therefore needs one branch for "no checklist", and nothing here ever
 * accuses a project of missing instrumentation on data it could not read.
 *
 * Both write endpoints return the whole recomputed checklist, so a dismissal or a restore
 * installs its own response rather than triggering a second read.
 */
export const instrumentationChecklistLogic = kea<instrumentationChecklistLogicType>([
    path(['products', 'ai_observability', 'frontend', 'instrumentationChecklist', 'instrumentationChecklistLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], teamLogic, ['currentTeamId']],
        actions: [featureFlagLogic, ['setFeatureFlags']],
    })),
    actions({
        dismissCheck: (check: AIObservabilityInstrumentationCheckEnumApi) => ({ check }),
        restoreCheck: (check: AIObservabilityInstrumentationCheckEnumApi) => ({ check }),
        setPendingCheck: (check: AIObservabilityInstrumentationCheckEnumApi | null) => ({ check }),
    }),
    loaders(({ values }) => ({
        checklist: [
            null as InstrumentationChecklistApi | null,
            {
                loadInstrumentationChecklist: async (
                    _: void,
                    breakpoint
                ): Promise<InstrumentationChecklistApi | null> => {
                    if (!values.checklistEnabled) {
                        return null
                    }
                    const response = await aiObservabilityInstrumentationChecklistRetrieve(String(values.currentTeamId))
                    breakpoint()
                    cachedVerdict = { at: performance.now(), teamId: values.currentTeamId, checklist: response }
                    return response
                },
            },
        ],
    })),
    reducers({
        pendingCheckKey: [
            null as AIObservabilityInstrumentationCheckEnumApi | null,
            {
                setPendingCheck: (_, { check }) => check,
            },
        ],
        lastLoadFailed: [
            false,
            {
                loadInstrumentationChecklist: () => false,
                loadInstrumentationChecklistSuccess: () => false,
                loadInstrumentationChecklistFailure: () => true,
            },
        ],
    }),
    selectors({
        checklistEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean =>
                !!featureFlags[FEATURE_FLAGS.AI_OBSERVABILITY_INSTRUMENTATION_CHECKLIST],
        ],
        checks: [
            (s) => [s.checklist],
            (checklist: InstrumentationChecklistApi | null): InstrumentationCheckApi[] => checklist?.checks ?? [],
        ],
        windowDays: [
            (s) => [s.checklist],
            (checklist: InstrumentationChecklistApi | null): number | null => checklist?.window_days ?? null,
        ],
        checklistBusy: [
            (s) => [s.checklistLoading, s.pendingCheckKey],
            (checklistLoading: boolean, pendingCheckKey: AIObservabilityInstrumentationCheckEnumApi | null): boolean =>
                checklistLoading || pendingCheckKey !== null,
        ],
        checklistCardState: [
            (s) => [s.checklistEnabled, s.checks],
            (checklistEnabled: boolean, checks: InstrumentationCheckApi[]): InstrumentationChecklistCardState => {
                if (!checklistEnabled || checks.length === 0) {
                    return 'hidden'
                }
                if (checks.some((check) => check.status === InstrumentationCheckStatusEnumApi.Warning)) {
                    return 'warnings'
                }
                // A dismissal is the team's judgement, not evidence the project passed anything, so
                // it must not turn a project whose every other check is still pending into 'passing'.
                const gradedOk = checks.some((check) => check.status === InstrumentationCheckStatusEnumApi.Ok)
                const stillPending = checks.some((check) => check.status === InstrumentationCheckStatusEnumApi.Pending)
                if (!gradedOk && stillPending) {
                    return 'collecting'
                }
                return 'passing'
            },
        ],
        warningForCheck: [
            (s) => [s.checklistEnabled, s.checks],
            (
                checklistEnabled: boolean,
                checks: InstrumentationCheckApi[]
            ): ((key: AIObservabilityInstrumentationCheckEnumApi) => InstrumentationCheckApi | null) => {
                if (!checklistEnabled) {
                    return () => null
                }
                return (key: AIObservabilityInstrumentationCheckEnumApi) =>
                    checks.find(
                        (check) => check.key === key && check.status === InstrumentationCheckStatusEnumApi.Warning
                    ) ?? null
            },
        ],
        // A failed first read stays invisible, so a retry is offered only for a refresh that
        // failed under a checklist already on screen. kea-loaders keeps the previous value on
        // failure, which is what makes the two cases distinguishable.
        refreshFailed: [
            (s) => [s.checklist, s.lastLoadFailed],
            (checklist: InstrumentationChecklistApi | null, lastLoadFailed: boolean): boolean =>
                checklist !== null && lastLoadFailed,
        ],
    }),
    listeners(({ actions, values }) => {
        async function writeCheck(
            check: AIObservabilityInstrumentationCheckEnumApi,
            write: (projectId: string, body: InstrumentationCheckActionApi) => Promise<InstrumentationChecklistApi>
        ): Promise<void> {
            // One request at a time. A repeat click would post twice, and a write racing a read
            // would have its recomputed checklist overwritten by the read's older response.
            if (values.checklistBusy) {
                return
            }
            actions.setPendingCheck(check)
            try {
                const recomputed = await write(String(values.currentTeamId), { check })
                cachedVerdict = { at: performance.now(), teamId: values.currentTeamId, checklist: recomputed }
                actions.loadInstrumentationChecklistSuccess(recomputed)
            } catch {
                // The read path stays silent so we never accuse a project on data we could not read,
                // but a click that visibly does nothing reads as a broken button.
                lemonToast.error('Could not update this check. Try again.')
            } finally {
                actions.setPendingCheck(null)
            }
        }

        return {
            setFeatureFlags: () => {
                // A staged-rollout flag is not part of the server-rendered app context, so on a
                // cold load it only arrives after mount. Fetch then rather than waiting for the
                // user to navigate.
                if (values.checklistEnabled && values.checklist === null && !values.checklistLoading) {
                    actions.loadInstrumentationChecklist()
                }
            },
            dismissCheck: ({ check }) => writeCheck(check, aiObservabilityInstrumentationChecklistDismissCreate),
            restoreCheck: ({ check }) => writeCheck(check, aiObservabilityInstrumentationChecklistRestoreCreate),
        }
    }),
    afterMount(({ actions, values }) => {
        // Loading before the flag resolves would hold `checklistLoading` true while the request
        // short-circuits to null, and the setFeatureFlags listener would then skip its own retry,
        // leaving the card hidden for good. On a cold page the flag arriving starts the first load.
        if (!values.checklistEnabled) {
            return
        }
        if (
            cachedVerdict &&
            cachedVerdict.teamId === values.currentTeamId &&
            performance.now() - cachedVerdict.at < VERDICT_TTL_MS
        ) {
            actions.loadInstrumentationChecklistSuccess(cachedVerdict.checklist)
            return
        }
        actions.loadInstrumentationChecklist()
    }),
])
