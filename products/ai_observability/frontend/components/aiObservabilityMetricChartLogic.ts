// LIMIT 2 is enough to tell one trace from several.
const BUCKET_TRACES_QUERY = `
    SELECT properties.$ai_trace_id AS trace_id, min(timestamp) AS first_seen
    FROM events
    WHERE ${TRACE_EVENTS} AND notEmpty(toString(properties.$ai_trace_id)) AND {filters}
    GROUP BY trace_id
    LIMIT 2
`

const HIDE_SUPPORT_TRACES: AnyPropertyFilter = {
    type: PropertyFilterType.HogQL,
    key: "isNull(properties.ai_support_impersonated) OR properties.ai_support_impersonated != 'true'",
}

