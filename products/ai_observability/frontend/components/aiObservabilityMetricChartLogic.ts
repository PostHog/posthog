export type aiObservabilityMetricChartLogicType = MakeLogicType<
    aiObservabilityMetricChartLogicValues,
    aiObservabilityMetricChartLogicActions,
    AIObservabilityMetricChartLogicProps,
    aiObservabilityMetricChartLogicMeta
>

export const aiObservabilityMetricChartLogic = kea<aiObservabilityMetricChartLogicType>([
    props({} as AIObservabilityMetricChartLogicProps),
    key((props) => props.metric ?? 'pickable'),
    path((key) => ['products', 'ai_observability', 'frontend', 'components', 'aiObservabilityMetricChartLogic', key]),
    connect(() => ({
        values: [aiObservabilitySharedLogic, ['dateFilter', 'shouldFilterTestAccounts', 'propertyFilters']],
        actions: [aiObservabilitySharedLogic, ['setDates'], traceDrawerLogic({ listId: 'traces' }), ['openRow']],
    })),
    actions({
        openBucketTrace: (label: string) => ({ label }),
        setMetric: (metric: MetricChartKey) => ({ metric }),
        zoomTo: (startLabel: string, endLabel: string) => ({ startLabel, endLabel }),
    }),
    reducers(() => ({
        metric: [
            'traces' as MetricChartKey,
            buildAiObservabilityStorageConfig('metricChart.metric'),
            { setMetric: (_, { metric }) => metric },
        ],
    })),
    selectors({
        activeMetric: [
            (s) => [s.metric, (_, props) => props.metric],
            (metric: MetricChartKey, pinned: MetricChartKey | undefined): MetricChartKey => pinned ?? metric,
        ],
        interval: [(s) => [s.dateFilter], ({ dateFrom, dateTo }) => metricChartInterval(dateFrom, dateTo)],
        canZoom: [(s) => [s.interval], (interval: IntervalType) => interval !== 'minute'],
        query: [
            (s) => [s.activeMetric, s.interval, s.dateFilter, s.shouldFilterTestAccounts, s.propertyFilters],
            (
                metric: MetricChartKey,
                interval: IntervalType,
                dateFilter: {
                    dateFrom: string | null
                    dateTo: string | null
                },
                shouldFilterTestAccounts: boolean,
                propertyFilters: AnyPropertyFilter[]
            ): TrendsQuery => ({
                kind: NodeKind.TrendsQuery,
                // The chosen metric first; the trace count decides which minute bars can open a trace.
                series: [METRIC_CHART_DEFINITIONS[metric].series, METRIC_CHART_DEFINITIONS.traces.series].map(
                    (series): EventsNode => ({
                        kind: NodeKind.EventsNode,
                        event: '$ai_generation',
                        name: '$ai_generation',
                        ...series,
                    })
                ),
                interval,
                dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo },
                filterTestAccounts: shouldFilterTestAccounts,
                properties: propertyFilters,
            }),
        ],
    }),
    listeners(({ actions, values }) => ({
        setMetric: ({ metric }) => {
            posthog.capture('llma metric chart metric changed', { metric })
        },
        zoomTo: ({ startLabel, endLabel }) => {
            const range = metricChartBucketRange(startLabel, endLabel, values.interval)
            posthog.capture('llma metric chart zoomed', { metric: values.activeMetric, from_interval: values.interval })
            actions.setDates(range.dateFrom, range.dateTo)
        },
        openBucketTrace: async ({ label }, breakpoint) => {
            const range = metricChartBucketRange(label, label, values.interval)
            const response = await performQuery<HogQLQuery>({
                kind: NodeKind.HogQLQuery,
                query: BUCKET_TRACES_QUERY,
                filters: {
                    dateRange: { date_from: range.dateFrom, date_to: range.dateTo },
                    filterTestAccounts: values.shouldFilterTestAccounts,
                    properties: values.propertyFilters,
                },
            })
            breakpoint()
            const rows = response.results ?? []
            if (rows.length !== 1) {
                return
            }
            const [traceId, firstSeen] = rows[0] as [string, string]
            posthog.capture('llma metric chart trace opened', { metric: values.activeMetric })
            actions.openRow({ traceId, timestamp: getTraceTimestamp(firstSeen), stepId: null })
        },
    })),
])
