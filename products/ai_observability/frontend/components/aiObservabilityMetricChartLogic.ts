export const aiObservabilityMetricChartLogic = kea<aiObservabilityMetricChartLogicType>([
    props({} as AIObservabilityMetricChartLogicProps),
    key((props) => props.metric ?? 'pickable'),
    path((key) => ['products', 'ai_observability', 'frontend', 'components', 'aiObservabilityMetricChartLogic', key]),
    connect(() => ({
        values: [
            aiObservabilitySharedLogic,
            ['dateFilter', 'shouldFilterTestAccounts', 'shouldFilterSupportTraces', 'propertyFilters'],
            traceDrawerLogic({ listId: 'traces' }),
            ['isEnabled as drawerEnabled'],
            userLogic,
            ['user'],
            teamLogic,
            ['weekStartDay'],
        ],
        actions: [aiObservabilitySharedLogic, ['setDates'], traceDrawerLogic({ listId: 'traces' }), ['openRow']],
    })),
    actions({
        setMetric: (metric: MetricChartKey) => ({ metric }),
        /** `endLabel` is the bar after the zoomed range, or null when it runs to the chart's end. */
        zoomTo: (startLabel: string, endLabel: string | null) => ({ startLabel, endLabel }),
    }),
    reducers(() => ({
        metric: [
            'traces' as MetricChartKey,
            buildAiObservabilityStorageConfig('metricChart.metric'),
            { setMetric: (_, { metric }) => metric },
        ],
    })),
    selectors({
        activeMetric: [
            (s) => [s.metric, (_, props) => props.metric],
            // A metric saved in the browser can outlive its option.
            (metric: MetricChartKey, pinned: MetricChartKey | undefined): MetricChartKey =>
                pinned ?? (metric in METRIC_CHART_DEFINITIONS ? metric : 'traces'),
        ],
        interval: [(s) => [s.dateFilter], ({ dateFrom, dateTo }) => metricChartInterval(dateFrom, dateTo)],
        canZoom: [(s) => [s.interval], (interval: IntervalType) => interval !== 'minute'],
        // The Users tab pins its metric, and its table counts each person's generations.
        usersTable: [
            () => [(_, props) => props.metric],
            (pinned: MetricChartKey | undefined): boolean => pinned === 'users',
        ],
        scopeFilters: [
            (s) => [s.propertyFilters, s.shouldFilterSupportTraces, s.user, s.usersTable],
            (
                propertyFilters: AnyPropertyFilter[],
                shouldFilterSupportTraces: boolean,
                user: UserType | null,
                usersTable: boolean
            ): AnyPropertyFilter[] =>
                // Same rule as the traces table: only support staff may see support traces. The Users table shows them.
                !usersTable && (user?.is_impersonated ? shouldFilterSupportTraces : true)
                    ? [...propertyFilters, HIDE_SUPPORT_TRACES]
                    : propertyFilters,
        ],
        filters: [
            (s) => [s.dateFilter, s.shouldFilterTestAccounts, s.scopeFilters],
            (
                dateFilter: { dateFrom: string | null; dateTo: string | null },
                shouldFilterTestAccounts: boolean,
                scopeFilters: AnyPropertyFilter[]
            ): HogQLFilters => ({
                dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo },
                filterTestAccounts: shouldFilterTestAccounts,
                properties: scopeFilters,
            }),
        ],
        scope: [
            (s) => [s.activeMetric, s.usersTable, s.propertyFilters, s.interval, s.weekStartDay, s.dateFilter],
            (
                metric: MetricChartKey,
                usersTable: boolean,
                propertyFilters: AnyPropertyFilter[],
                interval: IntervalType,
                weekStartDay: number,
                dateFilter: { dateFrom: string | null; dateTo: string | null }
            ): MetricChartScope => ({
                metric,
                usersTable,
                propertyFiltered: propertyFilters.length > 0,
                interval,
                weekStartDay,
                ...dateFilter,
            }),
        ],
        query: [
            (s) => [s.scope, s.filters],
            (scope: MetricChartScope, filters: HogQLFilters): HogQLQuery => ({
                kind: NodeKind.HogQLQuery,
                query: metricChartQuery(scope),
                filters,
            }),
        ],
    }),
    loaders(({ values }) => ({
        bucketTrace: [
            null as TraceListRow | null,
            {
                openBucketTrace: async ({ label }: { label: string }): Promise<TraceListRow | null> => {
                    const response = await performQuery<HogQLQuery>({
                        kind: NodeKind.HogQLQuery,
                        query: metricChartBucketTracesQuery(values.scope, label),
                        filters: values.filters,
                    }).catch(() => null)
                    if (!response) {
                        lemonToast.error("Couldn't open the trace. Click the bar to try again.")
                        return null
                    }
                    const rows = response.results ?? []
                    if (rows.length !== 1) {
                        return null
                    }
                    const [traceId, firstSeen] = rows[0] as [string, string]
                    return { traceId, timestamp: getTraceTimestamp(firstSeen), stepId: null }
                },
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        setMetric: ({ metric }) => {
            posthog.capture('llma metric chart metric changed', { metric })
        },
        zoomTo: ({ startLabel, endLabel }) => {
            posthog.capture('llma metric chart zoomed', { metric: values.activeMetric, from_interval: values.interval })
            actions.setDates(startLabel, endLabel ?? values.dateFilter.dateTo)
        },
        openBucketTraceSuccess: ({ bucketTrace }) => {
            if (!bucketTrace) {
                return
            }
            const { traceId, timestamp } = bucketTrace
            posthog.capture('llma metric chart trace opened', { metric: values.activeMetric })
            // The drawer only renders on the traces tab, so anywhere else the trace opens as a page.
            const onTracesTab = TRACE_DRAWER_LISTS.traces.pathMatcher.test(
                removeProjectIdIfPresent(router.values.location.pathname)
            )
            if (values.drawerEnabled && onTracesTab) {
                actions.openRow(bucketTrace)
            } else {
                router.actions.push(urls.aiObservabilityTrace(traceId, { timestamp: timestamp ?? undefined }))
            }
        },
    })),
])
