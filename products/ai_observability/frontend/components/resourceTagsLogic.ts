import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, type LogicWrapper } from 'kea'

import { lemonToast } from 'lib/lemon-ui/LemonToast'

import { tagsModel } from '~/models/tagsModel'

import {
    datasetsPartialUpdate,
    llmAnalyticsScoreDefinitionsPartialUpdate,
    aiObservabilityOfflineExperimentsPartialUpdate,
} from '../generated/api'
import { getApiErrorDetail } from '../scoreDefinitions/scoreDefinitionModalUtils'
import type { TaggedResource } from './resourceTagFilters'

export interface ResourceTagsLogicProps {
    entity: TaggedResource
    resourceId: string
    teamId: number
    tags: readonly string[]
    onSaved: () => void
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface resourceTagsLogicValues {
    draft: string[]
    error: string | null
    isOpen: boolean
    saving: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface resourceTagsLogicActions {
    loadTagsIfNeeded: () => {
        value: true
    } // tagsModel
    refreshTags: () => {
        value: true
    } // tagsModel
    close: () => {
        value: true
    }
    open: () => {
        value: true
    }
    save: () => {
        value: true
    }
    setDraft: (tags: string[]) => {
        tags: string[]
    }
    setError: (error: string | null) => {
        error: string | null
    }
    setSaving: (saving: boolean) => {
        saving: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface resourceTagsLogicMeta {
    key: string
}

export type resourceTagsLogicType = MakeLogicType<
    resourceTagsLogicValues,
    resourceTagsLogicActions,
    ResourceTagsLogicProps,
    resourceTagsLogicMeta
>

export const resourceTagsLogic: LogicWrapper<resourceTagsLogicType> = kea<resourceTagsLogicType>([
    props({} as ResourceTagsLogicProps),
    key(({ entity, resourceId, teamId }) => `${teamId}:${entity}:${resourceId}`),
    path((key) => ['products', 'ai_observability', 'resourceTagsLogic', key]),
    connect({ actions: [tagsModel, ['loadTagsIfNeeded', 'refreshTags']] }),
    actions({
        open: true,
        close: true,
        setDraft: (tags: string[]) => ({ tags }),
        save: true,
        setSaving: (saving: boolean) => ({ saving }),
        setError: (error: string | null) => ({ error }),
    }),
    reducers(({ props }) => ({
        isOpen: [false, { open: () => true, close: () => false }],
        draft: [[] as string[], { open: () => [...props.tags], setDraft: (_, { tags }) => tags }],
        saving: [false, { setSaving: (_, { saving }) => saving }],
        error: [null as string | null, { open: () => null, setError: (_, { error }) => error }],
    })),
    listeners(({ actions, values, props }) => ({
        open: () => actions.loadTagsIfNeeded(),
        save: async () => {
            if (values.saving) {
                return
            }
            actions.setSaving(true)
            actions.setError(null)
            try {
                const update =
                    props.entity === 'datasets'
                        ? datasetsPartialUpdate
                        : props.entity === 'scorers'
                          ? llmAnalyticsScoreDefinitionsPartialUpdate
                          : aiObservabilityOfflineExperimentsPartialUpdate
                await update(String(props.teamId), props.resourceId, { tags: values.draft })
                actions.refreshTags()
                props.onSaved()
                actions.close()
                lemonToast.success('Tags updated')
            } catch (error) {
                actions.setError(getApiErrorDetail(error) || 'Could not update tags. Please try again.')
            } finally {
                actions.setSaving(false)
            }
        },
    })),
])
