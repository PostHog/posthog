import type { TaggerApi } from '../generated/api.schemas'
import { getIntervalFromDateRange } from './types'

export interface TagRun {
    // Optional because the tagger detail page's loader (in this file) doesn't
    // select uuid — only the per-generation loader does, where it's needed
    // for collision-free row keys in the trace Tags tab.
    uuid?: string
    timestamp: string
    tags: string[]
    reasoning: string
    trace_id: string
    target_event_id: string
    tagger_id: string
    tagger_name: string
}

