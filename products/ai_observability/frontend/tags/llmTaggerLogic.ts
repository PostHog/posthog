export const llmTaggerLogic = kea<llmTaggerLogicType>([
    path(['products', 'ai_observability', 'taggers', 'llmTaggerLogic']),
    props({} as LLMTaggerLogicProps),
    key((props) => props.id),

    connect(() => ({
        values: [aiObservabilitySharedLogic, ['dateFilter'], teamLogic, ['currentTeamId']],
        actions: [aiObservabilitySharedLogic, ['setDates']],
    })),

    actions({
        setActiveTab: (tab: 'runs' | 'configuration') => ({ tab }),
        loadTagRuns: true,
        loadTagRunsSuccess: (runs: TagRun[]) => ({ runs }),
    }),

    loaders(({ props, values }) => ({
        tagger: [
            null as TaggerApi | null,
            {
                loadTagger: async () => {
                    try {
                        return await taggersRetrieve(String(values.currentTeamId), props.id)
                    } catch {
                        return null
                    }
                },
            },
        ],
    })),

    reducers({
        activeTab: [
            'runs' as string,
            {
                setActiveTab: (_, { tab }) => tab,
            },
        ],
        tagRuns: [
            [] as TagRun[],
            {
                loadTagRunsSuccess: (_, { runs }) => runs,
            },
        ],
        tagRunsLoading: [
            false,
            {
                loadTagRuns: () => true,
                loadTagRunsSuccess: () => false,
            },
        ],
    }),

    selectors({
        runsChartQuery: [
            (s, props) => [props.id, s.dateFilter],
            (id: string, dateFilter: { dateFrom: string | null; dateTo: string | null }): TrendsQuery => {
                const dateFrom = dateFilter.dateFrom || '-7d'
                const dateTo = dateFilter.dateTo || null
                const interval = getIntervalFromDateRange(dateFrom)

                return {
                    kind: NodeKind.TrendsQuery,
                    series: [
                        {
                            kind: NodeKind.EventsNode,
                            event: '$ai_tag',
                            math: 'total' as any,
                            properties: [
                                {
                                    key: '$ai_tagger_id',
                                    value: id,
                                    operator: PropertyOperator.Exact,
                                    type: PropertyFilterType.Event,
                                },
                            ],
                        },
                    ],
                    breakdownFilter: {
                        // Emit one breakdown row per event. If $ai_tags is empty, bucket under
                        // "(no tag)" so the chart still reflects that the tagger is running even
                        // when no tags matched (otherwise arrayJoin on [] drops the event).
                        breakdown:
                            "arrayJoin(if(length(JSONExtract(ifNull(properties.$ai_tags, '[]'), 'Array(String)')) = 0, ['(no tag)'], JSONExtract(ifNull(properties.$ai_tags, '[]'), 'Array(String)')))",
                        breakdown_type: 'hogql',
                    },
                    trendsFilter: {
                        // Stacked area makes the composition read naturally: total height = run
                        // volume, colored bands = tag share. Handles the "(no tag)" bucket cleanly
                        // without it looking like a stray zero-line.
                        display: ChartDisplayType.ActionsAreaGraph,
                    },
                    dateRange: {
                        date_from: dateFrom,
                        date_to: dateTo,
                    },
                    interval,
                }
            },
        ],
    }),

    listeners(({ props, actions, values }) => ({
        loadTagRuns: async () => {
            const dateFrom = values.dateFilter?.dateFrom || '-24h'
            const dateTo = values.dateFilter?.dateTo || null
            // Inline the tagger_id rather than using a `values` dict: parse_select
            // eagerly resolves all placeholders against `values` before
            // find_placeholders runs, which means combining `{tagger_id}` with
            // `{filters}` fails — `{filters}` is missing from `values` and the
            // whole query errors out, leaving the runs list silently empty.
            // escapeHogQLString returns the value already wrapped in single quotes.
            const escapedTaggerId = escapeHogQLString(props.id)
            const query: HogQLQuery = {
                kind: NodeKind.HogQLQuery,
                query: `
                    SELECT
                        timestamp,
                        properties.$ai_tags as tags,
                        properties.$ai_tag_reasoning as reasoning,
                        properties.$ai_trace_id as trace_id,
                        properties.$ai_target_event_id as target_event_id,
                        properties.$ai_tagger_id as tagger_id,
                        properties.$ai_tagger_name as tagger_name
                    FROM events
                    WHERE event = '$ai_tag'
                      AND properties.$ai_tagger_id = ${escapedTaggerId}
                      AND {filters}
                    ORDER BY timestamp DESC
                    LIMIT 100
                `,
                filters: {
                    dateRange: {
                        date_from: dateFrom,
                        date_to: dateTo,
                    },
                },
            }
            try {
                const response = await api.query(query)
                const runs = (response.results || []).map((row: any[]) => ({
                    timestamp: row[0],
                    tags: typeof row[1] === 'string' ? JSON.parse(row[1]) : row[1] || [],
                    reasoning: row[2] || '',
                    trace_id: row[3] || '',
                    target_event_id: row[4] || '',
                    tagger_id: row[5] || '',
                    tagger_name: row[6] || '',
                }))
                actions.loadTagRunsSuccess(runs)
            } catch {
                actions.loadTagRunsSuccess([])
            }
        },
        setDates: () => {
            actions.loadTagRuns()
        },
    })),

    afterMount(({ actions }) => {
        actions.loadTagger()
        actions.loadTagRuns()
        // Read initial tab from URL search params
        const { searchParams } = router.values
        if (searchParams.tab === 'configuration' || searchParams.tab === 'runs') {
            actions.setActiveTab(searchParams.tab)
        }
    }),
])
