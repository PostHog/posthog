export interface FeedbackViewLogicProps {
    traceId: string
}

/**
 * Collects the survey IDs to look up from the trace's survey events.
 *
 * Feedback surveys on a trace are captured by the app under test, so `$survey_id` holds
 * whatever that app sent. The surveys API filters on a list of UUIDs and rejects the whole
 * list when one entry is malformed, which would leave the tab with no feedback at all, so
 * drop the IDs that cannot belong to a survey.
 */
export function extractValidSurveyIds(surveyEvents: LLMTraceEvent[] | null): string[] {
    if (!surveyEvents) {
        return []
    }
    const ids = new Set<string>()
    for (const event of surveyEvents) {
        const surveyId = getSurveyIdFromEvent(event)
        if (surveyId && isUUIDLike(surveyId)) {
            ids.add(surveyId)
        }
    }
    return Array.from(ids)
}

