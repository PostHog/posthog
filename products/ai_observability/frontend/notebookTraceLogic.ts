import { MakeLogicType, connect, kea, key, path, props, selectors } from 'kea'

import { dayjs } from 'lib/dayjs'
import { isObject } from 'lib/utils/guards'

import { DataNodeLogicProps, dataNodeLogic } from '~/queries/nodes/DataNode/dataNodeLogic'
import { LLMTrace, NodeKind, TraceQuery } from '~/queries/schema/schema-general'

import type {
    ErrorTrackingQueryResponse,
    HogQLAutocompleteResponse,
    HogQLMetadataResponse,
    HogQLQueryResponse,
    HogQueryResponse,
    LogAttributesQueryResponse,
    LogValuesQueryResponse,
    MetricsQueryResponse,
    SessionsQueryResponse,
    TraceSpansAggregationQueryResponse,
    TraceSpansAttributeBreakdownQueryResponse,
    TraceSpansQueryResponse,
    TraceSpansTreeQueryResponse,
} from '../../../frontend/src/queries/schema/schema-general'
import { parserRecipesLogic } from './settings/parserRecipesLogic'

export interface NotebookTraceLogicProps {
    traceId: string
}

function traceQuery(traceId: string): TraceQuery {
    return {
        kind: NodeKind.TraceQuery,
        traceId,
        includeSentiment: true,
        dateRange: { date_from: dayjs.utc().subtract(1, 'year').startOf('day').toISOString() },
    }
}

function traceDataNodeProps(traceId: string): DataNodeLogicProps {
    return { query: traceQuery(traceId), key: `notebook-trace-${traceId}`, dataNodeCollectionId: traceId }
}

function isLLMTrace(value: unknown): value is LLMTrace {
    return isObject(value) && typeof value.id === 'string' && Array.isArray(value.events)
}

function firstTrace(response: unknown): LLMTrace | undefined {
    const first = isObject(response) && Array.isArray(response.results) ? response.results[0] : undefined
    return isLLMTrace(first) ? first : undefined
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface notebookTraceLogicValues {
    response:
        | ErrorTrackingQueryResponse
        | HogQLAutocompleteResponse
        | HogQLMetadataResponse
        | HogQLQueryResponse<any[]>
        | HogQueryResponse
        | LogAttributesQueryResponse
        | LogValuesQueryResponse
        | MetricsQueryResponse
        | Record<string, any>
        | SessionsQueryResponse
        | TraceSpansAggregationQueryResponse
        | TraceSpansAttributeBreakdownQueryResponse
        | TraceSpansQueryResponse
        | TraceSpansTreeQueryResponse
        | null // dataNodeLogic
    responseLoading: boolean // dataNodeLogic
    dataNodeProps: DataNodeLogicProps
    query: TraceQuery
    trace: LLMTrace | undefined
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface notebookTraceLogicMeta {
    key: any
    __keaTypeGenInternalSelectorTypes: {
        query: (traceId: any) => TraceQuery
        dataNodeProps: (traceId: any) => DataNodeLogicProps
        trace: (response: any) => LLMTrace | undefined
    }
}

export type notebookTraceLogicType = MakeLogicType<
    notebookTraceLogicValues,
    {},
    NotebookTraceLogicProps,
    notebookTraceLogicMeta
>

export const notebookTraceLogic = kea<notebookTraceLogicType>([
    props({} as NotebookTraceLogicProps),
    key((props) => props.traceId),
    path((key) => ['products', 'ai_observability', 'frontend', 'notebookTraceLogic', key]),
    connect((props: NotebookTraceLogicProps) => ({
        // A team's custom recipes reach the browser normalizer only while this logic is mounted, and a
        // notebook or profile page can show this widget before any other AI observability page loaded them.
        logic: [parserRecipesLogic],
        values: [dataNodeLogic(traceDataNodeProps(props.traceId)), ['response', 'responseLoading']],
    })),
    selectors({
        query: [(_, p) => [p.traceId], (traceId: string): TraceQuery => traceQuery(traceId)],
        dataNodeProps: [(_, p) => [p.traceId], (traceId: string): DataNodeLogicProps => traceDataNodeProps(traceId)],
        trace: [(s) => [s.response], (response: unknown): LLMTrace | undefined => firstTrace(response)],
    }),
])
