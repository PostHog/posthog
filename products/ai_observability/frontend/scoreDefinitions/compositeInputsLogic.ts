export const compositeInputsLogic = kea<compositeInputsLogicType>([
    path(['products', 'ai_observability', 'frontend', 'scoreDefinitions', 'compositeInputsLogic']),
    props({} as CompositeInputsLogicProps),
    key(({ id }) => `${getCurrentProjectId()}-${id}`),
    actions({
        setSearch: (search: string) => ({ search }),
        setTagFilters: (tagFilters: ResourceTagFilters) => ({ tagFilters }),
        loadOptions: true,
        loadVersions: (definitionId: string, cursor?: string) => ({ definitionId, cursor }),
        setVersionsLoading: (definitionId: string, loading: boolean) => ({ definitionId, loading }),
        validateFormula: (draft: ScoreDefinitionDraft) => ({ draft }),
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        tagFilters: [
            { tags: [], tag_match: 'any' } as ResourceTagFilters,
            { setTagFilters: (_, { tagFilters }) => tagFilters },
        ],
        versionsLoadingById: [
            {} as Record<string, boolean>,
            {
                setVersionsLoading: (state, { definitionId, loading }) => ({ ...state, [definitionId]: loading }),
            },
        ],
        optionsError: [
            null as string | null,
            {
                loadOptions: () => null,
                setSearch: () => null,
                loadOptionsFailure: (_, { error }) => error,
                loadOptionsSuccess: () => null,
            },
        ],
        versionsError: [
            null as string | null,
            { loadVersions: () => null, loadVersionsFailure: (_, { error }) => error, loadVersionsSuccess: () => null },
        ],
    }),
    loaders(({ props, values, actions }) => ({
        options: [
            null as Awaited<ReturnType<typeof llmAnalyticsScoreDefinitionsList>> | null,
            {
                loadOptions: async (_, breakpoint) => {
                    const page = await llmAnalyticsScoreDefinitionsList(getCurrentProjectId(), {
                        calculation: props.inputDefinitionId ? 'composite' : 'reported',
                        input_definition_id: props.inputDefinitionId,
                        search: values.search || undefined,
                        tags: JSON.stringify(values.tagFilters.tags),
                        tag_match: values.tagFilters.tag_match,
                        archived: false,
                        limit: 50,
                    })
                    breakpoint()
                    return page
                },
            },
        ],
        versions: [
            {} as Record<string, { results: ScoreDefinitionVersionApi[]; next_cursor: string | null }>,
            {
                loadVersions: async ({ definitionId, cursor }) => {
                    actions.setVersionsLoading(definitionId, true)
                    try {
                        const page = await llmAnalyticsScoreDefinitionsVersionsList(
                            getCurrentProjectId(),
                            definitionId,
                            {
                                cursor,
                                limit: 50,
                            }
                        )
                        return {
                            [definitionId]: {
                                results: [
                                    ...(cursor ? values.versions[definitionId]?.results || [] : []),
                                    ...page.results,
                                ],
                                next_cursor: page.next_cursor,
                            },
                        }
                    } finally {
                        actions.setVersionsLoading(definitionId, false)
                    }
                },
            },
        ],
        validation: [
            null as { fingerprint: string; error: string | null } | null,
            {
                validateFormula: async ({ draft }) => {
                    const body = {
                        kind: draft.kind,
                        composition: buildCompositionFromDraft(draft)!,
                        config: buildConfigFromDraft(draft),
                    }
                    const fingerprint = JSON.stringify(body)
                    posthog.capture('llma composite formula validation started', {
                        kind: draft.kind,
                        input_count: draft.inputs.length,
                    })
                    try {
                        await llmAnalyticsScoreDefinitionsValidateCompositionCreate(getCurrentProjectId(), body)
                        posthog.capture('llma composite formula validated', { kind: draft.kind, valid: true })
                        return { fingerprint, error: null }
                    } catch (error) {
                        posthog.capture('llma composite formula validated', { kind: draft.kind, valid: false })
                        return {
                            fingerprint,
                            error: getApiErrorDetail(error) || 'Could not validate the formula. Try again.',
                        }
                    }
                },
            },
        ],
    })),
    reducers({
        versions: [
            {} as Record<string, { results: ScoreDefinitionVersionApi[]; next_cursor: string | null }>,
            { loadVersionsSuccess: (state, { versions }) => ({ ...state, ...versions }) },
        ],
    }),
    listeners(({ actions }) => ({
        setSearch: async (_, breakpoint) => {
            await breakpoint(300)
            actions.loadOptions()
        },
        setTagFilters: () => actions.loadOptions(),
    })),
    afterMount(({ actions, props }) => {
        actions.loadOptions()
        props.initialDefinitionIds?.forEach((id) => actions.loadVersions(id))
    }),
])
