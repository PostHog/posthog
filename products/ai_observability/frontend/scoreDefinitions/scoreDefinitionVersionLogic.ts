export type scoreDefinitionVersionLogicType = MakeLogicType<
    scoreDefinitionVersionLogicValues,
    scoreDefinitionVersionLogicActions,
    ScoreDefinitionVersionLogicProps,
    scoreDefinitionVersionLogicMeta
>

export const scoreDefinitionVersionLogic = kea<scoreDefinitionVersionLogicType>([
    path(['products', 'ai_observability', 'frontend', 'scoreDefinitions', 'scoreDefinitionVersionLogic']),
    props({} as ScoreDefinitionVersionLogicProps),
    key((props: ScoreDefinitionVersionLogicProps) => `${props.teamId}-${props.scorerId}`),
    actions({
        loadCurrentDefinition: true,
        submit: true,
        beginSubmit: true,
        finishSubmit: true,
        setError: (error: string | null) => ({ error }),
    }),
    loaders(({ props }) => ({
        currentDefinition: [
            null as ScoreDefinitionApi | null,
            {
                loadCurrentDefinition: async (_, breakpoint): Promise<ScoreDefinitionApi | null> => {
                    const definition = await llmAnalyticsScoreDefinitionsRetrieve(props.teamId, props.scorerId)
                    breakpoint()
                    return props.teamId === getCurrentProjectId() ? definition : null
                },
            },
        ],
    })),
    reducers({
        currentDefinition: [null as ScoreDefinitionApi | null, { loadCurrentDefinition: () => null }],
        submitting: [false, { beginSubmit: () => true, finishSubmit: () => false }],
        error: [
            null as string | null,
            {
                setError: (_, { error }) => error,
                loadCurrentDefinition: () => null,
                loadCurrentDefinitionFailure: () => 'Could not load the current scorer version. Try again.',
            },
        ],
    }),
    listeners(({ actions, asyncActions, props, values }) => ({
        submit: async (_, breakpoint) => {
            if (
                values.submitting ||
                values.currentDefinitionLoading ||
                !values.currentDefinition ||
                props.teamId !== getCurrentProjectId()
            ) {
                return
            }
            const definition = values.currentDefinition
            const teamId = props.teamId
            actions.beginSubmit()
            actions.setError(null)
            try {
                const updated = await llmAnalyticsScoreDefinitionsNewVersionCreate(teamId, props.scorerId, {
                    config: definition.config,
                    base_version: definition.current_version,
                })
                breakpoint()
                if (getCurrentProjectId() !== teamId) {
                    return
                }
                lemonToast.success(`Created scorer version ${updated.current_version}.`)
                props.onSuccess?.(updated)
                props.onClose()
            } catch (error) {
                breakpoint()
                if (typeof error === 'object' && error !== null && 'status' in error && error.status === 409) {
                    await asyncActions.loadCurrentDefinition()
                    actions.setError('The current version changed. Review the new source version and confirm again.')
                } else {
                    actions.setError(getApiErrorDetail(error) || 'Could not create a new version. Try again.')
                }
            } finally {
                actions.finishSubmit()
            }
        },
    })),
    afterMount(({ actions }) => actions.loadCurrentDefinition()),
])
