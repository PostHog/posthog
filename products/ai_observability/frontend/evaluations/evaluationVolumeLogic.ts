/** Estimates how often an unsaved evaluation would run, from the generations its triggers matched last week. */
export const evaluationVolumeLogic = kea<evaluationVolumeLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'evaluations', 'evaluationVolumeLogic', key]),
    // Same props and key as the evaluation it estimates, so a template draft reads its own evaluation.
    props({} as LLMEvaluationLogicProps),
    key(llmEvaluationLogicKey),
    connect((props: LLMEvaluationLogicProps) => ({
        values: [llmEvaluationLogic(props), ['evaluation'], teamLogic, ['currentTeamId']],
    })),
    loaders(({ values, cache }) => ({
        counts: [
            null as ConditionCounts[] | null,
            {
                loadCounts: async (_: void, breakpoint) => {
                    await breakpoint(VOLUME_DEBOUNCE_MS)
                    const input = values.volumeInput
                    if (!input) {
                        return null
                    }
                    const controller = new AbortController()
                    const running = new Set<string>()
                    cache.disposables.add(
                        () => () => {
                            controller.abort()
                            running.forEach((queryId) => void cancelQueryOnServer(values.currentTeamId, queryId))
                        },
                        'volumeQueries',
                        { pauseOnPageHidden: false }
                    )
                    let counts: ConditionCounts[]
                    try {
                        counts = await Promise.all(
                            input.conditions.map(async (condition): Promise<ConditionCounts> => {
                                const queryId = uuid()
                                running.add(queryId)
                                const response = await performQuery(
                                    conditionVolumeQuery(condition, input.target),
                                    { signal: controller.signal },
                                    undefined,
                                    queryId
                                ).finally(() => running.delete(queryId))
                                const [generations = 0, units = generations] = (response.results ?? []).map(
                                    (series: { aggregated_value?: number }) => series.aggregated_value ?? 0
                                )
                                return { generations, units }
                            })
                        )
                    } catch (error) {
                        // A superseded load fails on the abort, so it ends here instead of showing an error.
                        breakpoint()
                        throw error
                    }
                    breakpoint()
                    return counts
                },
            },
        ],
    })),
    selectors({
        volumeInput: [
            (s) => [s.evaluation],
            (evaluation: EvaluationConfig | null): VolumeInput | null =>
                evaluation && !filtersOnContent(evaluation.conditions)
                    ? { conditions: evaluation.conditions, target: evaluationTarget(evaluation) }
                    : null,
        ],
        // Sampling changes only scale the counts, so the key leaves it out and moving the slider queries nothing.
        countsKey: [
            (s) => [s.volumeInput],
            (input: VolumeInput | null): string =>
                JSON.stringify(
                    input && {
                        target: input.target,
                        properties: input.conditions.map((condition) => condition.properties ?? []),
                    }
                ),
        ],
        volume: [
            (s) => [s.counts, s.volumeInput],
            (counts: ConditionCounts[] | null, input: VolumeInput | null): VolumeEstimate | null =>
                counts && input && counts.length === input.conditions.length
                    ? summarizeVolume(
                          counts.map((count, index) => ({
                              ...count,
                              rolloutPercentage: input.conditions[index].rollout_percentage ?? 0,
                          })),
                          input.target
                      )
                    : null,
        ],
    }),
    reducers({
        countsError: [
            false,
            {
                loadCounts: () => false,
                loadCountsSuccess: () => false,
                loadCountsFailure: () => true,
            },
        ],
    }),
    subscriptions(({ actions }) => ({
        countsKey: () => actions.loadCounts(),
    })),
])
