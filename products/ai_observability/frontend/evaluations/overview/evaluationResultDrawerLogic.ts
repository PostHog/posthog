export const evaluationResultDrawerLogic = kea<evaluationResultDrawerLogicType>([
    path(['products', 'ai_observability', 'frontend', 'evaluations', 'overview', 'evaluationResultDrawerLogic']),
    connect(() => ({
        values: [evaluationsOverviewLogic, ['request', 'currentTeamId', 'rowsById']],
        actions: [evaluationsOverviewLogic, ['loadOverviewSuccess', 'reloadOverview']],
    })),
    actions({
        openDrawer: (evaluationId: string) => ({ evaluationId }),
        closeDrawer: true,
        trackEmptyStateAction: (action: string, state: string) => ({ action, state }),
        prefetchDetails: (evaluationId: string) => ({ evaluationId }),
        loadDetails: (evaluationId: string, trigger: DetailsTrigger) => ({ evaluationId, trigger }),
        detailsRequested: (key: string, evaluationId: string) => ({ key, evaluationId }),
        detailsLoaded: (key: string, load: DetailsLoad) => ({ key, load }),
        resetDetails: true,
    }),
    reducers({
        openEvaluationId: [
            null as string | null,
            {
                openDrawer: (_, { evaluationId }) => evaluationId,
                closeDrawer: () => null,
            },
        ],
        // Keyed by evaluation and period, so reopening a drawer for the same range shows it at once.
        details: [
            {} as Record<string, DetailsLoad>,
            {
                detailsRequested: (state, { key }) => ({ ...state, [key]: { status: 'loading' } }),
                detailsLoaded: (state, { key, load }) => ({ ...state, [key]: load }),
                resetDetails: () => ({}),
            },
        ],
    }),
    selectors({
        openRow: [
            (s) => [s.openEvaluationId, s.rowsById],
            (openEvaluationId: string | null, rowsById: Map<string, EvaluationResultApi>): EvaluationResultApi | null =>
                (openEvaluationId && rowsById.get(openEvaluationId)) || null,
        ],
        openDetails: [
            (s) => [s.openEvaluationId, s.details, s.request],
            (
                openEvaluationId: string | null,
                details: Record<string, DetailsLoad>,
                request: OverviewRequest
            ): DetailsLoad | null =>
                openEvaluationId ? (details[detailsKey(openEvaluationId, request)] ?? null) : null,
        ],
    }),
    // pinned: every analytics event name and property in these listeners, because renaming one breaks dashboards.
    listeners(({ actions, values, cache }) => ({
        // A new period or scope can arrive while the drawer stays open, for example through browser Back. Its rows
        // are current only once the overview loads, which the graded check in `loadDetails` needs.
        loadOverviewSuccess: () => {
            if (values.openEvaluationId) {
                actions.loadDetails(values.openEvaluationId, 'open')
            }
        },
        // A refresh keeps the period, so the key alone would keep showing details from before it.
        reloadOverview: () => {
            // The backend caches details for a few minutes, so a period read before the refresh skips that cache next.
            cache.refreshKeys = new Set([...(cache.refreshKeys ?? []), ...Object.keys(values.details)])
            // A read still in flight started before the refresh, so its response must not land as current.
            cache.generation = (cache.generation ?? 0) + 1
            actions.resetDetails()
        },
        trackEmptyStateAction: ({ action, state }) => {
            posthog.capture('llma evaluation overview drawer empty action', { action, state })
        },
        openDrawer: ({ evaluationId }) => {
            const row = values.rowsById.get(evaluationId)
            posthog.capture('llma evaluation overview drawer opened', {
                summary_kind: row?.summary.kind,
                prefetched: values.details[detailsKey(evaluationId, values.request)]?.status === 'ready',
            })
            actions.loadDetails(evaluationId, 'open')
        },
        prefetchDetails: async ({ evaluationId }, breakpoint) => {
            // A pointer crossing the table on its way elsewhere moves on before this, and the next row cancels it.
            await breakpoint(PREFETCH_DELAY_MS)
            actions.loadDetails(evaluationId, 'prefetch')
        },
        loadDetails: ({ evaluationId, trigger }) => {
            const key = detailsKey(evaluationId, values.request)
            const current = values.details[key]
            // A failed read retries only when someone opens the drawer.
            if (current && (current.status !== 'error' || trigger === 'prefetch')) {
                return
            }
            // Without its row, for example after a failed refresh, the read would not know which endpoints apply. The next
            // overview that lands loads the open drawer again. Nothing graded shows a notice that needs no details.
            const row = values.rowsById.get(evaluationId)
            if (!row || row.gradedCount === 0) {
                return
            }
            if (trigger === 'prefetch') {
                // Each read holds one of the organization's query slots, so a sweep down the table must not start
                // one read per row it crosses.
                if (cache.prefetchingKey) {
                    return
                }
                cache.prefetchingKey = key
            }
            actions.detailsRequested(key, evaluationId)
        },
        detailsRequested: async ({ key, evaluationId }) => {
            const { date_from, date_to } = values.request.params
            const refresh = cache.refreshKeys?.has(key) === true
            const generation = cache.generation ?? 0
            const projectId = String(values.currentTeamId)
            const params = { date_from, date_to, ...(refresh ? { refresh: true } : {}) }
            // Each endpoint rejects an evaluation it does not apply to, so the row decides which ones to read.
            const summary = values.rowsById.get(evaluationId)?.summary
            const scale = summary && 'score' in summary ? summary.score?.scale : null
            const load = await Promise.all([
                summary?.kind === 'pass_rate'
                    ? evaluationsRunsRetrieve(projectId, evaluationId, {
                          ...params,
                          outcome: 'failed',
                          limit: RECENT_FAILURES_LIMIT,
                      }).then((runs) => runs.results)
                    : null,
                scale && scale.min < scale.max
                    ? evaluationsScoreDistributionRetrieve(projectId, evaluationId, params)
                    : null,
            ]).then(
                ([recentFailures, scoreDistribution]): DetailsLoad => ({
                    status: 'ready',
                    details: { recentFailures, scoreDistribution },
                }),
                (error: unknown): DetailsLoad => ({ status: 'error', failure: failureOf(error) })
            )
            if (cache.prefetchingKey === key) {
                cache.prefetchingKey = null
            }
            if (generation === (cache.generation ?? 0)) {
                // A failed read keeps the key, so the retry skips the cache too.
                if (load.status === 'ready') {
                    cache.refreshKeys?.delete(key)
                }
                actions.detailsLoaded(key, load)
            }
        },
    })),
])
