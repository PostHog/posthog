const MIN_RUNS_FOR_FAILING_STATUS = 3
const MAX_EVALUATION_CHART_SERIES = 10

/** One row from the stats query. Polarity-free by design — the query never claims a pass. */
export interface EvaluationStatsRow {
    evaluation_id: string
    runs_count: number
    applicable_count: number
    true_count: number
    applicability_rate: number
    score_count?: number
    score_mean?: number | null
    numeric_pass_count?: number
}

/** A stats row with the evaluation's own polarity applied. */
export interface EvaluationStats extends EvaluationStatsRow {
    pass_count: number
    pass_rate: number | null
}

export interface SummaryMetrics {
    total_runs: number
    overall_pass_rate: number | null
    failing_evaluations_count: number
}

type RawStatsRow = [
    evaluation_id: string,
    runs_count: number,
    applicable_count: number,
    true_count: number,
    score_count?: number,
    score_mean?: number | null,
    numeric_pass_count?: number,
]

function hasPassRate(evaluation: EvaluationConfig): boolean {
    return (
        evaluation.output_type === 'boolean' ||
        (evaluation.output_type === 'numeric' && !!evaluation.output_config.passing_rule)
    )
}

export type EvaluationMetricsLogicProps = Record<string, never>

function getIntervalFromDateRange(dateFrom: string | null): 'hour' | 'day' {
    if (!dateFrom) {
        return 'day'
    }

    // Handle "today" formats
    if (dateFrom === 'dStart' || dateFrom === '-0d' || dateFrom === '-0dStart') {
        return 'hour'
    }

    // Handle relative date strings like "-24h", "-1d", "-7d"
    const match = dateFrom.match(/^-(\d+)([hdwmy])/i)
    if (match) {
        const value = parseInt(match[1])
        const unit = match[2].toLowerCase()
        const hoursMap: Record<string, number> = { h: 1, d: 24, w: 168, m: 720, y: 8760 }
        const hours = value * (hoursMap[unit] || 24)
        return hours <= 24 ? 'hour' : 'day'
    }

    // Handle absolute dates
    const duration = dayjs.duration(dayjs().diff(dayjs(dateFrom)))
    return duration.asDays() <= 1 ? 'hour' : 'day'
}

function buildEvaluationBreakdownExpression(evaluations: EvaluationConfig[]): string {
    const evaluationNameCounts = new Map<string, number>()
    const evaluationNameIndexes = new Map<string, number>()

    for (const evaluation of evaluations) {
        evaluationNameCounts.set(evaluation.name, (evaluationNameCounts.get(evaluation.name) ?? 0) + 1)
    }

    const conditionsAndLabels = evaluations.flatMap((evaluation) => {
        const nameIndex = (evaluationNameIndexes.get(evaluation.name) ?? 0) + 1
        evaluationNameIndexes.set(evaluation.name, nameIndex)
        const label =
            evaluationNameCounts.get(evaluation.name) === 1 ? evaluation.name : `${evaluation.name} (${nameIndex})`

        return [`properties.$ai_evaluation_id = ${escapeHogQLString(evaluation.id)}`, escapeHogQLString(label)]
    })

    return `multiIf(${conditionsAndLabels.join(', ')}, toString(properties.$ai_evaluation_id))`
}

