/** The report history for one evaluation: loading, paging, and waiting for a report started with "Generate now". */
export const evaluationReportRunsLogic = kea<evaluationReportRunsLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'evaluations', 'evaluationReportRunsLogic', key]),
    props({} as EvaluationReportRunsLogicProps),
    key((props) => props.evaluationId),
    connect((props: EvaluationReportRunsLogicProps) => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            evaluationReportLogic({ evaluationId: props.evaluationId }),
            ['activeReport', 'reportsLoading'],
        ],
        actions: [evaluationReportLogic({ evaluationId: props.evaluationId }), ['loadReportsSuccess']],
    })),
    actions({
        setHasOlderReportRuns: (hasOlderReportRuns: boolean) => ({ hasOlderReportRuns }),
        setNextOlderOffset: (offset: number) => ({ offset }),
        startWaitingForNewReport: (since: string) => ({ since }),
        stopWaitingForNewReport: true,
    }),
    loaders(({ actions, values, cache }) => ({
        reportRuns: [
            [] as EvaluationReportRun[],
            {
                loadReportRuns: async (reportId: string) => {
                    const teamId = requireCurrentTeamId(values.currentTeamId)
                    const response = await llmAnalyticsEvaluationReportsRunsList(teamId.toString(), reportId, {
                        limit: REPORT_RUNS_PAGE_SIZE,
                    })
                    actions.setHasOlderReportRuns(!!response?.next)
                    actions.setNextOlderOffset(response?.results?.length ?? 0)
                    return response?.results || []
                },
                loadOlderReportRuns: async () => {
                    if (!values.activeReport) {
                        return values.reportRuns
                    }
                    const teamId = requireCurrentTeamId(values.currentTeamId)
                    const offset = values.nextOlderOffset
                    const response = await llmAnalyticsEvaluationReportsRunsList(
                        teamId.toString(),
                        values.activeReport.id,
                        { limit: REPORT_RUNS_PAGE_SIZE, offset }
                    )
                    const results = response?.results ?? []
                    // The offset moves by what the server returned, so a page of already-loaded runs still advances.
                    actions.setNextOlderOffset(offset + results.length)
                    actions.setHasOlderReportRuns(results.length > 0 && !!response?.next)
                    const loadedIds = new Set(values.reportRuns.map((run) => run.id))
                    return [...values.reportRuns, ...results.filter((run) => !loadedIds.has(run.id))]
                },
                // Puts new reports in front and refreshes the ones it sees again, so polling keeps older pages.
                loadNewestReportRuns: async (reportId: string, breakpoint) => {
                    const teamId = requireCurrentTeamId(values.currentTeamId)
                    let response
                    try {
                        response = await llmAnalyticsEvaluationReportsRunsList(
                            teamId.toString(),
                            reportId,
                            { limit: NEW_REPORT_POLL_PAGE_SIZE },
                            { signal: cache.pollAbort?.signal }
                        )
                    } catch {
                        // Stops quietly when the page has gone. Otherwise a missed poll keeps the list, since the next
                        // one runs 15 seconds later.
                        breakpoint()
                        return values.reportRuns
                    }
                    const fresh = response?.results ?? []
                    const freshById = new Map(fresh.map((run) => [run.id, run]))
                    const loadedIds = new Set(values.reportRuns.map((run) => run.id))
                    const added = fresh.filter((run) => !loadedIds.has(run.id))
                    return [...added, ...values.reportRuns.map((run) => freshById.get(run.id) ?? run)]
                },
            },
        ],
        // The server's time for the request. The new report is the first run created after it.
        generateResult: [
            null as string | null,
            {
                generateReport: async (reportId: string) => {
                    const teamId = requireCurrentTeamId(values.currentTeamId)
                    const response = await llmAnalyticsEvaluationReportsGenerateCreate(teamId.toString(), reportId)
                    return response?.requested_at ?? null
                },
            },
        ],
    })),
    reducers({
        hasOlderReportRuns: [
            false,
            {
                setHasOlderReportRuns: (_, { hasOlderReportRuns }) => hasOlderReportRuns,
            },
        ],
        nextOlderOffset: [
            0,
            {
                setNextOlderOffset: (_, { offset }) => offset,
            },
        ],
        reportRunsLoadFailed: [
            false,
            {
                loadReportRuns: () => false,
                loadReportRunsSuccess: () => false,
                loadReportRunsFailure: () => true,
            },
        ],
        olderReportRunsLoadFailed: [
            false,
            {
                loadOlderReportRuns: () => false,
                loadOlderReportRunsSuccess: () => false,
                loadOlderReportRunsFailure: () => true,
                loadReportRuns: () => false,
            },
        ],
        // When "Generate now" was accepted, by the server's clock, so a browser clock that runs ahead can't hide the
        // new report. The first run created after it ends the wait.
        waitingForNewReportSince: [
            null as string | null,
            {
                startWaitingForNewReport: (_, { since }) => since,
                stopWaitingForNewReport: () => null,
            },
        ],
    }),
    selectors({
        isWritingReport: [
            (s) => [s.generateResultLoading, s.waitingForNewReportSince],
            (generateResultLoading: boolean, waitingForNewReportSince: string | null): boolean =>
                generateResultLoading || waitingForNewReportSince !== null,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadReportsSuccess: ({ reports }) => {
            const active = reports.find((report: EvaluationReport) => !report.deleted)
            if (active) {
                actions.loadReportRuns(active.id)
            }
        },
        generateReport: () => {
            evaluationReportTracking.generateRequested()
        },
        generateReportSuccess: ({ generateResult: requestedAt, payload: reportId }) => {
            if (!reportId || !requestedAt) {
                return
            }
            actions.startWaitingForNewReport(requestedAt)
            const deadline = Date.now() + NEW_REPORT_POLL_TIMEOUT_MS
            cache.finalCheck = false
            cache.failedSeenAt = {}
            // The setup runs again when a hidden tab comes back. Every check is scheduled, never run inside the
            // setup, so giving up can dispose this registration once it exists.
            cache.disposables.add(() => {
                const check = (): void => {
                    if (Date.now() > deadline) {
                        // Stop polling, then let one last fetch finish before deciding whether the report arrived.
                        cache.disposables.dispose(NEW_REPORT_POLL)
                        cache.pollAbort = null
                        cache.finalCheck = true
                        actions.loadNewestReportRuns(reportId)
                        return
                    }
                    // One poll at a time, so a slow endpoint doesn't pile up requests.
                    if (!values.reportRunsLoading) {
                        cache.pollAbort = new AbortController()
                        actions.loadNewestReportRuns(reportId)
                    }
                }
                const first = setTimeout(check, 0)
                const timer = setInterval(check, NEW_REPORT_POLL_INTERVAL_MS)
                return () => {
                    clearTimeout(first)
                    clearInterval(timer)
                    cache.pollAbort?.abort()
                }
            }, NEW_REPORT_POLL)
        },
        loadNewestReportRunsSuccess: ({ reportRuns }) => {
            const since = values.waitingForNewReportSince
            if (since === null) {
                return
            }
            const newRuns = reportRuns.filter((run) => createdAfter(run, since))
            if (cache.finalCheck) {
                cache.finalCheck = false
                actions.stopWaitingForNewReport()
                if (newRuns.length === 0) {
                    lemonToast.info('The new report is taking longer than usual. Refresh the page later to see it.')
                }
                return
            }
            // Pending means delivery hasn't run, and a fresh failure can still be retried, so neither ends the wait.
            const failedSeenAt: Record<string, number> = cache.failedSeenAt
            const settled = newRuns.some((run) => {
                if (run.delivery_status === 'pending') {
                    return false
                }
                if (run.delivery_status !== 'failed') {
                    return true
                }
                failedSeenAt[run.id] ??= Date.now()
                return Date.now() - failedSeenAt[run.id] > FAILED_DELIVERY_FINAL_MS
            })
            if (settled) {
                actions.stopWaitingForNewReport()
            }
        },
        stopWaitingForNewReport: () => {
            cache.disposables.dispose(NEW_REPORT_POLL)
        },
        generateReportFailure: () => {
            lemonToast.error('Failed to trigger report generation. Please try again.')
        },
    })),
    // The reports may have loaded before this logic mounted, and then their success action has already passed.
    afterMount(({ actions, values }) => {
        if (values.activeReport && !values.reportsLoading) {
            actions.loadReportRuns(values.activeReport.id)
        }
    }),
])
