export const evaluationBackfillsLogic = kea<evaluationBackfillsLogicType>([
    path((key) => ['products', 'ai_observability', 'evaluations', 'evaluationBackfillsLogic', key]),
    props({} as EvaluationBackfillsLogicProps),
    key((props) => props.evaluationId),

    connect((props: EvaluationBackfillsLogicProps) => ({
        values: [llmEvaluationLogic({ evaluationId: props.evaluationId }), ['evaluation'], teamLogic, ['timezone']],
        actions: [llmEvaluationLogic({ evaluationId: props.evaluationId }), ['loadEvaluationSuccess']],
    })),

    actions({
        loadBackfills: (background: boolean = false) => ({ background }),
        loadBackfillsSuccess: (backfills: EvaluationBackfillApi[]) => ({ backfills }),
        loadBackfillsFailure: (error: string) => ({ error }),
        requestEstimate: true,
        requestEstimateSuccess: (
            estimate: EvaluationBackfillEstimateApi,
            requestedWindow: BackfillWindow | null = null
        ) => ({
            estimate,
            requestedWindow,
        }),
        requestEstimateFailure: (error: string | null) => ({ error }),
        createBackfill: true,
        createBackfillDone: (succeeded: boolean) => ({ succeeded }),
        cancelBackfill: (id: string) => ({ id }),
        transitionBackfillDone: (id: string) => ({ id }),
        expandBackfill: (id: string) => ({ id }),
        collapseBackfill: (id: string) => ({ id }),
        setWindowRange: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setConditions: (conditions: EvaluationConditionSet[]) => ({ conditions }),
        seedConditions: (conditions: EvaluationConditionSet[]) => ({ conditions }),
        setRerunExisting: (rerunExisting: boolean) => ({ rerunExisting }),
    }),

    reducers({
        backfills: [[] as EvaluationBackfillApi[], { loadBackfillsSuccess: (_, { backfills }) => backfills }],
        backfillsError: [
            null as string | null,
            {
                loadBackfills: () => null,
                loadBackfillsSuccess: () => null,
                loadBackfillsFailure: (_, { error }) => error,
            },
        ],
        backfillsLoading: [
            false,
            {
                loadBackfills: (state, { background }) => (background ? state : true),
                loadBackfillsSuccess: () => false,
                loadBackfillsFailure: () => false,
            },
        ],
        pollFailures: [0, { loadBackfillsSuccess: () => 0, loadBackfillsFailure: (state) => state + 1 }],
        estimate: [
            null as EvaluationBackfillEstimateApi | null,
            {
                requestEstimate: () => null,
                requestEstimateSuccess: (_, { estimate }) => estimate,
                // A failed create leaves the counted window on screen so the user can retry it.
                createBackfillDone: (state, { succeeded }) => (succeeded ? null : state),
            },
        ],
        requestedWindow: [
            null as BackfillWindow | null,
            {
                requestEstimate: () => null,
                requestEstimateSuccess: (_, { requestedWindow }) => requestedWindow,
            },
        ],
        estimateError: [
            null as string | null,
            {
                requestEstimate: () => null,
                requestEstimateSuccess: () => null,
                requestEstimateFailure: (_, { error }) => error,
            },
        ],
        estimateLoading: [
            false,
            {
                requestEstimate: () => true,
                requestEstimateSuccess: () => false,
                requestEstimateFailure: () => false,
            },
        ],
        creatingBackfill: [false, { createBackfill: () => true, createBackfillDone: () => false }],
        windowDateFrom: [DEFAULT_WINDOW_DATE_FROM as string | null, { setWindowRange: (_, { dateFrom }) => dateFrom }],
        windowDateTo: [null as string | null, { setWindowRange: (_, { dateTo }) => dateTo }],
        conditions: [
            [] as EvaluationConditionSet[],
            {
                seedConditions: (_, { conditions }) => conditions,
                setConditions: (_, { conditions }) => conditions,
            },
        ],
        conditionsDirty: [false, { setConditions: () => true }],
        rerunExisting: [false, { setRerunExisting: (_, { rerunExisting }) => rerunExisting }],
        expandedBackfillIds: [
            [] as string[],
            {
                expandBackfill: (state, { id }) => (state.includes(id) ? state : [...state, id]),
                collapseBackfill: (state, { id }) => state.filter((expandedId) => expandedId !== id),
            },
        ],
        transitioningIds: [
            [] as string[],
            {
                cancelBackfill: (state, { id }) => [...state, id],
                transitionBackfillDone: (state, { id }) => state.filter((i) => i !== id),
            },
        ],
    }),

    selectors({
        hasActiveBackfill: [
            (s) => [s.backfills],
            (backfills: EvaluationBackfillApi[]): boolean => backfills.some((b) => b.status === 'running'),
        ],
        unit: [
            (s) => [s.estimate, s.evaluation],
            (
                estimate: EvaluationBackfillEstimateApi | null,
                evaluation: EvaluationConfig | null
            ): EvaluationTargetEnumApi => estimate?.unit ?? evaluation?.target ?? 'generation',
        ],
        startDisabledReason: [
            (s) => [s.hasActiveBackfill, s.conditions, s.estimate, s.estimateLoading, s.estimateError],
            (
                hasActiveBackfill: boolean,
                conditions: EvaluationConditionSet[],
                estimate: EvaluationBackfillEstimateApi | null,
                estimateLoading: boolean,
                estimateError: string | null
            ): string | undefined => {
                if (hasActiveBackfill) {
                    return 'This evaluation already has a running backfill'
                }
                // Checked before the count, which reads as an empty range rather than as a 0% sample.
                if (hasUnsetConditionRollout(conditions)) {
                    return 'Set a sampling percentage above 0% for every condition set'
                }
                if (estimateLoading) {
                    return 'Counting matching units'
                }
                if (estimateError) {
                    return estimateError
                }
                if (!estimate) {
                    return 'Pick a time range to see how many units match'
                }
                if (estimate.total_units === 0) {
                    return 'Nothing in this range matches these conditions'
                }
                return undefined
            },
        ],
        clampedWindow: [
            (s) => [s.estimate, s.requestedWindow, s.timezone],
            (
                estimate: EvaluationBackfillEstimateApi | null,
                requestedWindow: BackfillWindow | null,
                timezone: string
            ): { start: string; end: string } | null => {
                if (!estimate || !requestedWindow) {
                    return null
                }
                if (
                    estimate.window_start === requestedWindow.window_start &&
                    estimate.window_end === requestedWindow.window_end
                ) {
                    return null
                }
                // The server counted a shorter span than the picker asked for, so name the span it counted.
                const format = backfillRangeDateFormat(estimate.window_start, estimate.window_end, dayjs())
                return {
                    start: dayjs(estimate.window_start).tz(timezone).format(format),
                    end: dayjs(estimate.window_end).tz(timezone).format(format),
                }
            },
        ],
    }),

    listeners(({ actions, props, values, cache }) => {
        /** Arms the next poll off the list the logic last saw, so a failed request keeps the poll
         * alive instead of ending it. */
        const schedulePoll = (): void => {
            if (!values.hasActiveBackfill) {
                cache.disposables.dispose(POLL_KEY)
                return
            }
            const delay = pollDelayMs(values.pollFailures)
            cache.disposables.add(() => {
                const timerId = window.setTimeout(() => actions.loadBackfills(true), delay)
                return () => window.clearTimeout(timerId)
            }, POLL_KEY)
        }
        return {
            loadEvaluationSuccess: () => {
                if (!values.conditionsDirty && values.evaluation) {
                    actions.seedConditions(values.evaluation.conditions.map(toBackfillCondition))
                }
            },
            loadBackfills: async ({ background }) => {
                const teamId = teamLogic.values.currentTeamId
                if (!teamId) {
                    return
                }
                const wasActive = values.hasActiveBackfill
                try {
                    const response = await evaluationsBackfillsList(String(teamId), props.evaluationId, {
                        limit: BACKFILL_PAGE_SIZE,
                    })
                    actions.loadBackfillsSuccess(response.results ?? [])
                    if (wasActive && !values.hasActiveBackfill) {
                        // A finished run changed which units already have a result, so the count is stale.
                        cache.lastEstimate = null
                        actions.requestEstimate()
                    }
                } catch (error) {
                    const message = backfillErrorMessage(error, 'Couldn’t load backfills. Try again.')
                    actions.loadBackfillsFailure(message)
                    if (!background) {
                        // A poll fails on its own in the background, where the inline error is enough.
                        lemonToast.error(message)
                    }
                }
            },
            loadBackfillsSuccess: schedulePoll,
            loadBackfillsFailure: schedulePoll,
            seedConditions: () => actions.requestEstimate(),
            setWindowRange: () => actions.requestEstimate(),
            setConditions: () => actions.requestEstimate(),
            setRerunExisting: () => actions.requestEstimate(),
            requestEstimate: async (_, breakpoint) => {
                const teamId = teamLogic.values.currentTeamId
                if (!teamId || !values.windowDateFrom) {
                    // Nothing was asked for, so there is no error to report, only a count to stop.
                    actions.requestEstimateFailure(null)
                    return
                }
                await breakpoint(ESTIMATE_DEBOUNCE_MS)
                const request = {
                    ...resolveWindow(values.windowDateFrom, values.windowDateTo, values.timezone),
                    conditions: toRequestConditions(values.conditions),
                    rerun_existing: values.rerunExisting,
                }
                const requestKey = JSON.stringify(request)
                if (cache.lastEstimate && cache.lastEstimateKey === requestKey) {
                    // Every edit recounts. An edit that leaves the request identical, such as a
                    // filter put back the way it was, keeps the count it already has.
                    actions.requestEstimateSuccess(cache.lastEstimate, request)
                    return
                }
                try {
                    const estimate = await evaluationsBackfillsEstimateCreate(
                        String(teamId),
                        props.evaluationId,
                        request
                    )
                    breakpoint()
                    cache.lastEstimateKey = requestKey
                    cache.lastEstimate = estimate
                    actions.requestEstimateSuccess(estimate, request)
                } catch (error) {
                    breakpoint()
                    // No toast: the count reruns on every edit, and `estimateError` shows inline.
                    actions.requestEstimateFailure(backfillErrorMessage(error, 'Couldn’t count this range. Try again.'))
                }
            },
            createBackfill: async () => {
                const teamId = teamLogic.values.currentTeamId
                const estimate = values.estimate
                if (!teamId || !estimate) {
                    actions.createBackfillDone(false)
                    return
                }
                let succeeded = false
                try {
                    // The window the server clamped for the estimate is the one it just counted.
                    await evaluationsBackfillsCreate(String(teamId), props.evaluationId, {
                        window_start: estimate.window_start,
                        window_end: estimate.window_end,
                        conditions: toRequestConditions(values.conditions),
                        rerun_existing: values.rerunExisting,
                    })
                    succeeded = true
                    // The units this run covers now have a result, so the count it started from is stale.
                    cache.lastEstimate = null
                    lemonToast.success('Backfill started')
                    actions.loadBackfills()
                } catch (error) {
                    lemonToast.error(backfillErrorMessage(error, 'Couldn’t start the backfill. Try again.'))
                    // A concurrent backfill can be the cause (only one may run at a time), so refresh
                    // the table to show it.
                    actions.loadBackfills(true)
                } finally {
                    actions.createBackfillDone(succeeded)
                }
            },
            cancelBackfill: async ({ id }) => {
                const teamId = teamLogic.values.currentTeamId
                try {
                    if (teamId) {
                        await evaluationsBackfillsCancelCreate(String(teamId), props.evaluationId, id)
                        actions.loadBackfills(true)
                    }
                } catch (error) {
                    lemonToast.error(backfillErrorMessage(error, 'Couldn’t cancel the backfill. Try again.'))
                } finally {
                    actions.transitionBackfillDone(id)
                }
            },
        }
    }),

    afterMount(({ actions, values }) => {
        actions.loadBackfills()
        if (values.evaluation) {
            actions.seedConditions(values.evaluation.conditions.map(toBackfillCondition))
        }
    }),
])
