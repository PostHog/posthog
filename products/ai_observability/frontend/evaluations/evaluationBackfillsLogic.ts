// Keeps progress counts fresh while a backfill dispatches, without hammering the API when idle.
const ACTIVE_POLL_INTERVAL_MS = 10_000
const MAX_POLL_INTERVAL_MS = 60_000
const POLL_KEY = 'backfillPoll'
const BACKFILL_PAGE_SIZE = 100
const DEFAULT_WINDOW_DATE_FROM = '-7d'
// Long enough that typing a custom date or dragging the sampling slider counts once, at the end.
const ESTIMATE_DEBOUNCE_MS = 500

interface BackfillWindow {
    window_start: string
    window_end: string
}

/** The backfill API rejects anything the editor or the stored config carries alongside a condition
 * set, compiled bytecode for one. */
function toBackfillCondition(condition: EvaluationConditionSet): EvaluationConditionSet {
    return {
        id: condition.id,
        rollout_percentage: condition.rollout_percentage,
        properties: condition.properties,
    }
}

function toRequestConditions(conditions: EvaluationConditionSet[]): EvaluationConditionApi[] {
    return normalizeConditionRollouts(conditions).map((condition) => ({
        ...condition,
        // The editor types property filters as a union, the request type as plain objects. They
        // agree at runtime, so only this field is cast.
        properties: condition.properties as EvaluationConditionApiPropertiesItem[] | undefined,
    }))
}

/** Turn the picker's DateFilter tokens (`-7d`, an ISO date) into the ISO instants the API accepts.
 * Relative presets anchor on the project's own calendar day, so the timezone has to come along. */
function resolveWindow(dateFrom: string | null, dateTo: string | null, timezone: string): BackfillWindow {
    const bound = (value: string | null, fallback: dayjs.Dayjs): string =>
        ((value && dateStringToDayJs(value, timezone)) || fallback).toISOString()
    return {
        window_start: bound(dateFrom, dayjs().subtract(30, 'day')),
        window_end: bound(dateTo, dayjs()),
    }
}

function backfillErrorMessage(error: unknown, fallback: string): string {
    // `formattedRetryAfter` already reads as "in 30s" or "later", so the sentence adds no preposition.
    if (error instanceof ApiError && error.formattedRetryAfter) {
        return `Too many requests. Try again ${error.formattedRetryAfter}.`
    }
    return evaluationErrorMessage(error, fallback)
}

/** Each consecutive list failure doubles the wait, so an API that is already struggling is not
 * polled at full rate. The wait returns to the base interval as soon as one load succeeds. */
function pollDelayMs(consecutiveFailures: number): number {
    return Math.min(ACTIVE_POLL_INTERVAL_MS * 2 ** Math.max(consecutiveFailures - 1, 0), MAX_POLL_INTERVAL_MS)
}

