// Keeps progress counts fresh while a backfill dispatches, without hammering the API when idle.
const ACTIVE_POLL_INTERVAL_MS = 10_000
const POLL_KEY = 'backfillPoll'
const BACKFILL_PAGE_SIZE = 100
// The tab's promise is a count before you commit, so it opens on a range rather than on nothing.
const DEFAULT_WINDOW_DATE_FROM = '-7d'

/** The backfill API takes a condition set on its own terms; anything the editor or the stored
 * config carries alongside (compiled bytecode, for one) is rejected. */
function toBackfillCondition(condition: EvaluationConditionSet): EvaluationConditionSet {
    return {
        id: condition.id,
        rollout_percentage: condition.rollout_percentage,
        properties: condition.properties,
    }
}

function toRequestConditions(conditions: EvaluationConditionSet[]): EvaluationConditionApi[] {
    return conditions.map((condition) => ({
        ...condition,
        // The editor types property filters as a discriminated union, while the generated request
        // type wants plain objects. The two agree at runtime, so only this field is cast.
        properties: condition.properties as EvaluationConditionApiPropertiesItem[] | undefined,
    }))
}

/** Turn a DateFilter token (`-7d`, an ISO date) into an ISO instant the API accepts. Relative
 * presets anchor on the project's own calendar day, so the timezone has to come along. */
function resolveWindowBound(value: string | null, fallback: dayjs.Dayjs, timezone: string): string {
    return ((value && dateStringToDayJs(value, timezone)) || fallback).toISOString()
}

function backfillErrorMessage(error: unknown, fallback: string): string {
    // The estimate endpoint is throttled, so a 429 is a routine outcome while a range is adjusted.
    if (error instanceof ApiError && error.formattedRetryAfter) {
        return `Too many requests. Try again in ${error.formattedRetryAfter}.`
    }
    return evaluationErrorMessage(error, fallback)
}

