/**
 * The real traffic an unsaved evaluation would run on, and the results of testing it on some of those runs. It
 * reads the evaluation and never changes it.
 */
export const evaluationPreviewLogic = kea<evaluationPreviewLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'evaluations', 'evaluationPreviewLogic', key]),
    // Same props and key as the evaluation it previews, so a template draft reads its own evaluation.
    props({} as LLMEvaluationLogicProps),
    key(llmEvaluationLogicKey),
    connect((props: LLMEvaluationLogicProps) => ({
        values: [llmEvaluationLogic(props), ['evaluation'], teamLogic, ['currentTeamId']],
    })),
    loaders(({ values }) => ({
        samples: [
            null as PreviewRow[] | null,
            {
                loadSamples: async (_: void, breakpoint) => {
                    await breakpoint(SAMPLE_DEBOUNCE_MS)
                    const { evaluation, currentTeamId } = values
                    if (!evaluation || !currentTeamId) {
                        return null
                    }
                    const response = await evaluationsSampleTrafficCreate(currentTeamId.toString(), {
                        ...scope(evaluation),
                        count: SAMPLE_COUNT,
                    })
                    breakpoint()
                    return response.results.map(toRow)
                },
            },
        ],
        testResults: [
            null as Record<string, TestHogResultItemApi> | null,
            {
                testRows: async ({ auto }: { auto: boolean }, breakpoint) => {
                    if (auto) {
                        await breakpoint(HOG_RETEST_DEBOUNCE_MS)
                    }
                    const { evaluation, currentTeamId, rows } = values
                    const kind = testableKind(evaluation)
                    if (!evaluation || !currentTeamId || !kind || rows.length === 0) {
                        return null
                    }
                    const teamId = currentTeamId.toString()
                    const outputConfig = evaluation.output_config as TestHogRequestApi['output_config']
                    const response =
                        kind === 'hog' && evaluation.evaluation_type === 'hog'
                            ? await evaluationsTestHogCreate(teamId, {
                                  ...scope(evaluation),
                                  source: evaluation.evaluation_config.source,
                                  output_type: evaluation.output_type as TestHogRequestApi['output_type'],
                                  output_config: outputConfig,
                                  allows_na: evaluation.output_config.allows_na ?? false,
                                  sample_ids: rows.slice(0, HOG_TEST_LIMIT).map((row) => row.sampleId),
                              })
                            : await evaluationsTestOnSampleCreate(teamId, {
                                  ...scope(evaluation),
                                  evaluation_type: 'llm_judge',
                                  evaluation_config:
                                      evaluation.evaluation_config as EvaluationTestOnSampleRequestApi['evaluation_config'],
                                  model_configuration:
                                      evaluation.model_configuration as EvaluationTestOnSampleRequestApi['model_configuration'],
                                  output_type:
                                      evaluation.output_type as EvaluationTestOnSampleRequestApi['output_type'],
                                  output_config: outputConfig as EvaluationTestOnSampleRequestApi['output_config'],
                                  sample_ids: rows.slice(0, JUDGE_TEST_LIMIT).map((row) => row.sampleId),
                              })
                    breakpoint()
                    if (!auto) {
                        // pinned: analytics event name and properties, because usage reviews read them
                        posthog.capture('llma evaluation create preview tested', {
                            kind,
                            target: evaluation.target,
                            runs: response.results.length,
                            errors: response.results.filter((result) => result.error).length,
                        })
                    }
                    return Object.fromEntries(response.results.map((result) => [result.sample_id, result]))
                },
            },
        ],
    })),
    reducers({
        samplesError: [
            false,
            {
                loadSamples: () => false,
                loadSamplesSuccess: () => false,
                loadSamplesFailure: () => true,
            },
        ],
        testError: [
            null as string | null,
            {
                testRows: () => null,
                testRowsFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        rows: [(s) => [s.samples], (samples: PreviewRow[] | null): PreviewRow[] => samples ?? []],
        // The traffic changes with what it runs on, not with the check, so editing a prompt queries nothing.
        samplesKey: [
            (s) => [s.evaluation],
            (evaluation: EvaluationConfig | null): string =>
                JSON.stringify(
                    evaluation && {
                        conditions: evaluation.conditions,
                        target: evaluation.target,
                        target_config: evaluation.target_config,
                    }
                ),
        ],
        // Results belong to the config they ran with, so any change to it clears them.
        testKey: [
            (s) => [s.evaluation],
            (evaluation: EvaluationConfig | null): string =>
                JSON.stringify(
                    evaluation && {
                        type: evaluation.evaluation_type,
                        config: evaluation.evaluation_config,
                        output: [evaluation.output_type, evaluation.output_config],
                        model: evaluation.model_configuration,
                        target: evaluation.target,
                    }
                ),
        ],
    }),
    subscriptions(({ actions, values }) => {
        // Hog costs no model call, so its results follow every edit. A judge result only changes on a click.
        const retest = (): void => {
            if (testableKind(values.evaluation) === 'hog') {
                actions.testRows({ auto: true })
            } else {
                actions.testRowsSuccess(null)
            }
        }
        return {
            samplesKey: () => actions.loadSamples(),
            testKey: retest,
            rows: retest,
        }
    }),
])
