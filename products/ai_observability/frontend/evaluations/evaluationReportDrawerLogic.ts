// pinned: URL search param. Email and Slack links carry it, so renaming it breaks links already sent.
export const REPORT_RUN_PARAM = 'report_run'
const LINK_SEARCH_MAX_RUNS = 100
const CLOSE_ON_ESCAPE = 'closeOnEscape'

export interface EvaluationReportDrawerLogicProps {
    evaluationId: string
}

export interface ReportDrawerPosition {
    index: number
    total: number
}

export type ReportStepDirection = 'previous' | 'next'

function writeReportParam(runId: string | null): void {
    const { location, searchParams, hashParams } = router.values
    const nextParams = { ...searchParams }
    if (runId) {
        nextParams[REPORT_RUN_PARAM] = runId
    } else {
        delete nextParams[REPORT_RUN_PARAM]
    }
    router.actions.push(location.pathname, nextParams, hashParams)
}

