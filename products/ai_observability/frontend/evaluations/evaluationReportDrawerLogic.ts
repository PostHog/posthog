export const evaluationReportDrawerLogic = kea<evaluationReportDrawerLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'evaluations', 'evaluationReportDrawerLogic', key]),
    props({} as EvaluationReportDrawerLogicProps),
    key((props) => props.evaluationId),
    connect((props: EvaluationReportDrawerLogicProps) => ({
        values: [
            evaluationReportLogic({ evaluationId: props.evaluationId }),
            ['reportsLoading', 'reportsLoadFailed', 'activeReport'],
            evaluationReportRunsLogic({ evaluationId: props.evaluationId }),
            [
                'reportRuns',
                'reportRunsLoading',
                'hasOlderReportRuns',
                'reportRunsLoadFailed',
                'olderReportRunsLoadFailed',
            ],
        ],
        actions: [
            evaluationReportLogic({ evaluationId: props.evaluationId }),
            ['loadReports'],
            evaluationReportRunsLogic({ evaluationId: props.evaluationId }),
            ['loadOlderReportRuns', 'loadOlderReportRunsSuccess', 'loadReportRunsSuccess', 'loadReportRuns'],
        ],
    })),
    actions({
        openRun: (runId: string, source: ReportDrawerSource) => ({ runId, source }),
        stepTo: (direction: ReportStepDirection) => ({ direction }),
        close: true,
        retryLoad: true,
        searchOlder: true,
    }),
    reducers({
        // A link pages back this many runs on its own, so a link to a deleted report can't load the whole history.
        searchLimit: [
            LINK_SEARCH_PAGE_RUNS as number,
            {
                searchOlder: (limit) => limit + LINK_SEARCH_PAGE_RUNS,
            },
        ],
    }),
    selectors({
        openRunId: [
            () => [router.selectors.searchParams],
            (searchParams: Record<string, unknown>): string | null => {
                const value = searchParams[REPORT_RUN_PARAM]
                return typeof value === 'string' && value ? value : null
            },
        ],
        openIndex: [
            (s) => [s.reportRuns, s.openRunId],
            (reportRuns: EvaluationReportRun[], openRunId: string | null): number =>
                openRunId ? reportRuns.findIndex((run) => run.id === openRunId) : -1,
        ],
        openRun: [
            (s) => [s.reportRuns, s.openIndex],
            (reportRuns: EvaluationReportRun[], openIndex: number): EvaluationReportRun | null =>
                openIndex < 0 ? null : reportRuns[openIndex],
        ],
        // Previous and next follow the list, which is newest first, so previous is the newer report.
        previousRun: [
            (s) => [s.reportRuns, s.openIndex],
            (reportRuns: EvaluationReportRun[], openIndex: number): EvaluationReportRun | null =>
                openIndex <= 0 ? null : reportRuns[openIndex - 1],
        ],
        nextRun: [
            (s) => [s.reportRuns, s.openIndex],
            (reportRuns: EvaluationReportRun[], openIndex: number): EvaluationReportRun | null =>
                openIndex < 0 ? null : (reportRuns[openIndex + 1] ?? null),
        ],
        position: [
            (s) => [s.reportRuns, s.openIndex, s.hasOlderReportRuns],
            (
                reportRuns: EvaluationReportRun[],
                openIndex: number,
                hasOlderReportRuns: boolean
            ): ReportDrawerPosition | null =>
                openIndex < 0 ? null : { index: openIndex, total: reportRuns.length, more: hasOlderReportRuns },
        ],
        // The last loaded report can still step older, because the next page loads on the way.
        canStepOlder: [
            (s) => [s.nextRun, s.openRun, s.hasOlderReportRuns],
            (
                nextRun: EvaluationReportRun | null,
                openRun: EvaluationReportRun | null,
                hasOlderReportRuns: boolean
            ): boolean => !!nextRun || (!!openRun && hasOlderReportRuns),
        ],
        runLoadFailed: [
            (s) => [s.openRun, s.reportsLoadFailed, s.reportRunsLoadFailed, s.olderReportRunsLoadFailed],
            (
                openRun: EvaluationReportRun | null,
                reportsLoadFailed: boolean,
                reportRunsLoadFailed: boolean,
                olderReportRunsLoadFailed: boolean
            ): boolean => !openRun && (reportsLoadFailed || reportRunsLoadFailed || olderReportRunsLoadFailed),
        ],
        canSearchOlder: [
            (s) => [s.hasOlderReportRuns, s.reportRuns, s.searchLimit],
            (hasOlderReportRuns: boolean, reportRuns: EvaluationReportRun[], searchLimit: number): boolean =>
                hasOlderReportRuns && reportRuns.length < searchLimit,
        ],
        searchPaused: [
            (s) => [s.openRunId, s.openRun, s.hasOlderReportRuns, s.canSearchOlder, s.reportRunsLoading],
            (
                openRunId: string | null,
                openRun: EvaluationReportRun | null,
                hasOlderReportRuns: boolean,
                canSearchOlder: boolean,
                reportRunsLoading: boolean
            ): boolean => !!openRunId && !openRun && hasOlderReportRuns && !canSearchOlder && !reportRunsLoading,
        ],
        isSearchingForRun: [
            (s) => [s.openRunId, s.openRun, s.reportsLoading, s.reportRunsLoading, s.canSearchOlder, s.runLoadFailed],
            (
                openRunId: string | null,
                openRun: EvaluationReportRun | null,
                reportsLoading: boolean,
                reportRunsLoading: boolean,
                canSearchOlder: boolean,
                runLoadFailed: boolean
            ): boolean =>
                !!openRunId && !openRun && !runLoadFailed && (reportsLoading || reportRunsLoading || canSearchOlder),
        ],
    }),
    listeners(({ actions, cache, values }) => ({
        openRun: ({ runId, source }) => {
            cache.nextSource = source
            if (runId !== values.openRunId) {
                writeReportParam(runId)
            }
        },
        stepTo: ({ direction }) => {
            const target = direction === 'next' ? values.nextRun : values.previousRun
            if (!target && direction === 'next' && values.canStepOlder) {
                cache.stepOlderAfterLoad = true
                actions.loadOlderReportRuns()
                return
            }
            if (target) {
                cache.steps = (cache.steps ?? 0) + 1
                evaluationReportTracking.drawerStepped(direction)
                writeReportParam(target.id)
            }
        },
        close: () => {
            writeReportParam(null)
        },
        searchOlder: () => {
            actions.loadOlderReportRuns()
        },
        retryLoad: () => {
            if (values.reportsLoadFailed) {
                actions.loadReports()
            } else if (values.olderReportRunsLoadFailed) {
                actions.loadOlderReportRuns()
            } else if (values.activeReport) {
                actions.loadReportRuns(values.activeReport.id)
            }
        },
        loadReportRunsSuccess: () => {
            if (values.openRunId && !values.openRun && values.canSearchOlder) {
                actions.loadOlderReportRuns()
            }
        },
        loadOlderReportRunsSuccess: () => {
            if (cache.stepOlderAfterLoad) {
                cache.stepOlderAfterLoad = false
                if (values.nextRun) {
                    actions.stepTo('next')
                }
                return
            }
            if (values.openRunId && !values.openRun && values.canSearchOlder) {
                actions.loadOlderReportRuns()
            }
        },
    })),
    subscriptions(({ actions, cache, values }) => ({
        openRunId: (openRunId: string | null, previous: string | null | undefined) => {
            if (!openRunId) {
                if (previous && cache.openedAt) {
                    evaluationReportTracking.drawerClosed({
                        seconds_open: Math.round((Date.now() - cache.openedAt) / 1000),
                        steps: cache.steps ?? 0,
                    })
                    cache.openedAt = null
                }
                cache.disposables.dispose(CLOSE_ON_ESCAPE)
                return
            }
            if (!previous) {
                cache.openedAt = Date.now()
                cache.steps = 0
                cache.trackOpen = cache.nextSource ?? takeNextDrawerSource() ?? 'link'
                cache.nextSource = null
                cache.disposables.add(() => {
                    const closeOnEscape = (event: KeyboardEvent): void => {
                        // An open trace drawer sits on top, so Escape closes that one first.
                        if (shouldCloseOnEscape(event) && !router.values.searchParams.trace) {
                            actions.close()
                        }
                    }
                    document.addEventListener('keydown', closeOnEscape)
                    return () => document.removeEventListener('keydown', closeOnEscape)
                }, CLOSE_ON_ESCAPE)
            }
            if (!values.openRun && values.canSearchOlder && !values.reportRunsLoading) {
                actions.loadOlderReportRuns()
            }
        },
        // The open is tracked once the run is known, so a link's delivery status and age are recorded too.
        openRun: (openRun: EvaluationReportRun | null) => {
            if (openRun && cache.trackOpen) {
                evaluationReportTracking.drawerOpened({
                    source: cache.trackOpen,
                    delivery_status: openRun.delivery_status,
                    has_destination: (values.activeReport?.delivery_targets.length ?? 0) > 0,
                    report_age_hours: Math.round((Date.now() - new Date(openRun.created_at).getTime()) / 3_600_000),
                })
                cache.trackOpen = null
            }
        },
    })),
])
