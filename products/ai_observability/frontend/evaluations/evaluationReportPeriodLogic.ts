export interface evaluationReportPeriodLogicValues {
    currentTeamId: number | null // teamLogic
    timezone: string // teamLogic
    periodResults: ReportPeriodResults | null
    periodResultsFailed: boolean
    periodResultsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface evaluationReportPeriodLogicActions {
    loadPeriodResults: () => any
    loadPeriodResultsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadPeriodResultsSuccess: (
        periodResults: {
            buckets: string[]
            interval: EvaluationsOverviewIntervalEnumApi
            row: EvaluationResultApi | null
        },
        payload?: any
    ) => {
        periodResults: {
            buckets: string[]
            interval: EvaluationsOverviewIntervalEnumApi
            row: EvaluationResultApi | null
        }
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface evaluationReportPeriodLogicMeta {
    key: string
}

export type evaluationReportPeriodLogicType = MakeLogicType<
    evaluationReportPeriodLogicValues,
    evaluationReportPeriodLogicActions,
    EvaluationReportPeriodLogicProps,
    evaluationReportPeriodLogicMeta
>

/** Live results over one report's period, read from the overview endpoint, which buckets two days or less by hour. */
export const evaluationReportPeriodLogic = kea<evaluationReportPeriodLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'evaluations', 'evaluationReportPeriodLogic', key]),
    props({} as EvaluationReportPeriodLogicProps),
    key((props) => `${props.evaluationId}:${props.runId}`),
    connect(() => ({
        values: [teamLogic, ['currentTeamId', 'timezone']],
    })),
    loaders(({ props, values }) => ({
        periodResults: [
            null as ReportPeriodResults | null,
            {
                loadPeriodResults: async () => {
                    const overview = await evaluationsOverviewRetrieve(String(values.currentTeamId), {
                        date_from: props.periodStart,
                        date_to: props.periodEnd,
                        evaluation_ids: [props.evaluationId],
                    })
                    return {
                        row: overview.evaluations.find((row) => row.id === props.evaluationId) ?? null,
                        buckets: overview.buckets,
                        interval: overview.interval,
                    }
                },
            },
        ],
    })),
    reducers({
        periodResultsFailed: [
            false,
            {
                loadPeriodResults: () => false,
                loadPeriodResultsFailure: () => true,
            },
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadPeriodResults()
    }),
])
