import { MakeLogicType, afterMount, connect, kea, key, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { evaluationsOverviewRetrieve } from '../generated/api'
import type { EvaluationResultApi } from '../generated/api.schemas'
import type { EvaluationsOverviewIntervalEnumApi } from '../generated/api.schemas'
import type { BucketInterval } from './overview/evaluationOverviewDisplay'

export interface EvaluationReportPeriodLogicProps {
    evaluationId: string
    runId: string
    periodStart: string
    periodEnd: string
}

export interface ReportPeriodResults {
    row: EvaluationResultApi | null
    buckets: string[]
    interval: BucketInterval
}

