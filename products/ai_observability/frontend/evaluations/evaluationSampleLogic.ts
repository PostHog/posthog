import { MakeLogicType, actions, connect, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { subscriptions } from 'kea-subscriptions'

import { uuid } from 'lib/utils/dom'
import { teamLogic } from 'scenes/teamLogic'

import { cancelQueryOnServer } from '~/queries/nodes/DataNode/dataNodeLogic'
import { performQuery } from '~/queries/query'
import { EventsQuery, NodeKind } from '~/queries/schema/schema-general'
import type { AnyPropertyFilter, EventType } from '~/types'

import { VOLUME_LOOKBACK_DAYS, filtersOnContent } from './evaluationVolume'
import { type LLMEvaluationLogicProps, llmEvaluationLogic, llmEvaluationLogicKey } from './llmEvaluationLogic'
import type { EvaluationConfig } from './types'

/** Enough recent generations to flip through without querying again. */
const SAMPLE_LIMIT = 10
const SAMPLE_DEBOUNCE_MS = 600

export interface SampleGeneration {
    id: string
    properties: EventType['properties']
    timestamp: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface evaluationSampleLogicValues {
    evaluation: EvaluationConfig | null // llmEvaluationLogic
    currentTeamId: number | null // teamLogic
    sampleFilters: AnyPropertyFilter[] | null
    sampleIndex: number
    samples: SampleGeneration[] | null
    samplesError: boolean
    samplesLoading: boolean
    sample: SampleGeneration | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface evaluationSampleLogicActions {
    showNextSample: () => {
        value: true
    }
    loadSamples: (_: void) => void
    loadSamplesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSamplesSuccess: (
        samples: SampleGeneration[] | null,
        payload?: void
    ) => {
        samples: SampleGeneration[] | null
        payload?: void
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface evaluationSampleLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        sampleFilters: (evaluation: EvaluationConfig | null) => AnyPropertyFilter[] | null
        sample: (samples: SampleGeneration[] | null, sampleIndex: number) => SampleGeneration | null
    }
}

export type evaluationSampleLogicType = MakeLogicType<
    evaluationSampleLogicValues,
    evaluationSampleLogicActions,
    LLMEvaluationLogicProps,
    evaluationSampleLogicMeta
>

/** Recent generations an unsaved evaluation would match, so the instructions can be written against real data. */
export const evaluationSampleLogic = kea<evaluationSampleLogicType>([
    path((key) => ['products', 'ai_observability', 'frontend', 'evaluations', 'evaluationSampleLogic', key]),
    props({} as LLMEvaluationLogicProps),
    key(llmEvaluationLogicKey),
    connect((props: LLMEvaluationLogicProps) => ({
        values: [llmEvaluationLogic(props), ['evaluation'], teamLogic, ['currentTeamId']],
    })),
    actions({
        showNextSample: true,
    }),
    loaders(({ values, cache }) => ({
        samples: [
            null as SampleGeneration[] | null,
            {
                loadSamples: async (_: void, breakpoint) => {
                    await breakpoint(SAMPLE_DEBOUNCE_MS)
                    const filters = values.sampleFilters
                    if (!filters) {
                        return null
                    }
                    const query: EventsQuery = {
                        kind: NodeKind.EventsQuery,
                        select: ['*'],
                        event: '$ai_generation',
                        properties: filters,
                        after: `-${VOLUME_LOOKBACK_DAYS}d`,
                        orderBy: ['timestamp DESC'],
                        limit: SAMPLE_LIMIT,
                    }
                    const controller = new AbortController()
                    const queryId = uuid()
                    cache.disposables.add(
                        () => () => {
                            controller.abort()
                            void cancelQueryOnServer(values.currentTeamId, queryId)
                        },
                        'sampleQuery',
                        { pauseOnPageHidden: false }
                    )
                    let response
                    try {
                        response = await performQuery(query, { signal: controller.signal }, undefined, queryId)
                    } catch (error) {
                        // A superseded load fails on the abort, so it ends here instead of showing an error.
                        breakpoint()
                        throw error
                    }
                    breakpoint()
                    return (response.results ?? []).map((row) => {
                        const event = row[0] as EventType
                        return {
                            id: event.uuid ?? event.id,
                            properties: event.properties,
                            timestamp: event.timestamp,
                        }
                    })
                },
            },
        ],
    })),
    reducers({
        sampleIndex: [
            0,
            {
                showNextSample: (index) => index + 1,
                loadSamplesSuccess: () => 0,
            },
        ],
        samplesError: [
            false,
            {
                loadSamples: () => false,
                loadSamplesSuccess: () => false,
                loadSamplesFailure: () => true,
            },
        ],
    }),
    selectors({
        // The first condition set stands for the rest: a sample only has to show what the instructions will read.
        sampleFilters: [
            (s) => [s.evaluation],
            (evaluation: EvaluationConfig | null): AnyPropertyFilter[] | null =>
                evaluation && !filtersOnContent(evaluation.conditions)
                    ? ((evaluation.conditions[0]?.properties ?? []) as AnyPropertyFilter[])
                    : null,
        ],
        sample: [
            (s) => [s.samples, s.sampleIndex],
            (samples: SampleGeneration[] | null, sampleIndex: number): SampleGeneration | null =>
                samples?.length ? samples[sampleIndex % samples.length] : null,
        ],
    }),
    subscriptions(({ actions }) => ({
        sampleFilters: (next: AnyPropertyFilter[] | null, previous: AnyPropertyFilter[] | null | undefined) => {
            if (JSON.stringify(next) !== JSON.stringify(previous)) {
                actions.loadSamples()
            }
        },
    })),
])
