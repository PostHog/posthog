export const evaluationSuggestionsLogic = kea<evaluationSuggestionsLogicType>([
    path(['products', 'ai_observability', 'evaluations', 'suggestions', 'evaluationSuggestionsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], llmProviderKeysLogic, ['activeProviderKey']],
        actions: [traceDrawerLogic({ listId: SUGGESTION_EXAMPLES_LIST }), ['setRows', 'openRow']],
    })),

    actions({
        openExamples: (suggestion: EvalSuggestionApi) => ({ suggestion }),
        openJudgeConfirm: (suggestion: EvalSuggestionApi) => ({ suggestion }),
        closeJudgeConfirm: true,
        acceptSuggestion: (suggestion: EvalSuggestionApi) => ({ suggestion }),
        dismissSuggestion: (suggestion: EvalSuggestionApi, reason: EvalSuggestionDismissReasonEnumApi | null) => ({
            suggestion,
            reason,
        }),
        suggestionRemoved: (suggestionId: string) => ({ suggestionId }),
        suggestionActionFailed: (error: string) => ({ error }),
    }),

    loaders(({ values }) => ({
        suggestionList: [
            null as EvalSuggestionListApi | null,
            {
                loadEvalSuggestions: async () => await api.evaluationSuggestionsList(String(values.currentTeamId)),
            },
        ],
        evalSuggestionEstimate: [
            null as EvalSuggestionEstimateApi | null,
            {
                loadEvalSuggestionEstimate: async (suggestionId: string, breakpoint) => {
                    const estimate = await api.evaluationSuggestionsAcceptEstimateRetrieve(
                        String(values.currentTeamId),
                        suggestionId
                    )
                    breakpoint()
                    return estimate
                },
            },
        ],
    })),

    reducers({
        suggestionList: {
            suggestionRemoved: (state, { suggestionId }) =>
                state && { ...state, results: state.results.filter((existing) => existing.id !== suggestionId) },
        },
        // Stays true through a retry, so the error line keeps its button while the reload runs.
        suggestionListLoadFailed: [
            false,
            {
                loadEvalSuggestionsSuccess: () => false,
                loadEvalSuggestionsFailure: () => true,
            },
        ],
        evalSuggestionEstimate: {
            openJudgeConfirm: () => null,
        },
        estimateError: [
            null as string | null,
            {
                loadEvalSuggestionEstimate: () => null,
                loadEvalSuggestionEstimateFailure: (_, { errorObject }) =>
                    evaluationErrorMessage(errorObject, "Couldn't estimate the cost."),
            },
        ],
        // One slot for the whole list: every card's buttons wait while any change runs, so none is sent twice.
        inFlight: [
            null as SuggestionInFlight | null,
            {
                acceptSuggestion: (_, { suggestion }) => ({ suggestionId: suggestion.id, action: 'accept' }),
                dismissSuggestion: (_, { suggestion }) => ({ suggestionId: suggestion.id, action: 'dismiss' }),
                suggestionRemoved: () => null,
                suggestionActionFailed: () => null,
            },
        ],
        judgeConfirm: [
            null as EvalSuggestionApi | null,
            {
                openJudgeConfirm: (_, { suggestion }) => suggestion,
                closeJudgeConfirm: () => null,
                suggestionRemoved: () => null,
            },
        ],
        judgeConfirmError: [
            null as string | null,
            {
                openJudgeConfirm: () => null,
                acceptSuggestion: () => null,
                suggestionActionFailed: (_, { error }) => error,
            },
        ],
    }),

    selectors({
        // Judges run on the project's own key, so a refused judge points to the key settings when no key works.
        judgeConfirmNeedsProviderKey: [
            (s) => [s.judgeConfirmError, s.activeProviderKey],
            (judgeConfirmError: string | null, activeProviderKey: LLMProviderKey | null | undefined): boolean =>
                judgeConfirmError !== null && activeProviderKey?.state !== 'ok',
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        loadEvalSuggestionsSuccess: ({ suggestionList }) => {
            for (const suggestion of suggestionList?.results ?? []) {
                if (suggestion.status === 'proposed' && !cache.shownSuggestionIds.has(suggestion.id)) {
                    cache.shownSuggestionIds.add(suggestion.id)
                    captureSuggestionEvent('llma eval suggestion shown', suggestion)
                }
            }
            if (suggestionList?.pending && suggestionList.results.length === 0) {
                cache.disposables.add(() => {
                    const timer = window.setTimeout(() => actions.loadEvalSuggestions(), PENDING_POLL_INTERVAL_MS)
                    return () => window.clearTimeout(timer)
                }, 'pendingPoll')
            }
        },

        openExamples: ({ suggestion }) => {
            const rows: TraceListRow[] = suggestion.evidence.map(({ trace_id, reason }) => ({
                traceId: trace_id,
                timestamp: null,
                stepId: null,
                label: reason,
            }))
            if (rows.length === 0) {
                return
            }
            actions.setRows(rows)
            actions.openRow(rows[0])
            captureSuggestionEvent('llma eval suggestion examples opened', suggestion)
        },

        openJudgeConfirm: ({ suggestion }) => {
            actions.loadEvalSuggestionEstimate(suggestion.id)
        },

        acceptSuggestion: async ({ suggestion }) => {
            let accepted
            try {
                accepted = await api.evaluationSuggestionsAcceptCreate(String(values.currentTeamId), suggestion.id)
            } catch (error) {
                const message = evaluationErrorMessage(error, "Couldn't add the eval. Try again.")
                // The judge confirm shows the error itself, with the key settings when the key is the cause.
                if (!values.judgeConfirm) {
                    lemonToast.error(message)
                }
                actions.suggestionActionFailed(message)
                return
            }
            captureSuggestionEvent('llma eval suggestion accepted', suggestion)
            actions.suggestionRemoved(suggestion.id)
            // The list and the overview only fetch on mount, so they would miss the new eval on the way back.
            llmEvaluationsLogic.findMounted()?.actions.loadEvaluations()
            markEvaluationsOverviewStale()
            globalSetupLogic.findMounted()?.actions.markTaskAsCompleted(SetupTaskId.SetUpLlmEvaluation)
            router.actions.push(urls.aiObservabilityEvaluation(accepted.evaluation_id))
        },

        dismissSuggestion: async ({ suggestion, reason }) => {
            try {
                await api.evaluationSuggestionsDismissCreate(String(values.currentTeamId), suggestion.id, { reason })
            } catch (error) {
                const message = evaluationErrorMessage(error, "Couldn't dismiss the suggestion. Try again.")
                lemonToast.error(message)
                actions.suggestionActionFailed(message)
                return
            }
            captureSuggestionEvent('llma eval suggestion dismissed', suggestion, { reason })
            actions.suggestionRemoved(suggestion.id)
        },
    })),

    afterMount(({ actions, cache }) => {
        // A new mount is a new page view, so each suggestion counts as shown once more.
        cache.shownSuggestionIds = new Set<string>()
        actions.loadEvalSuggestions()
    }),
])
