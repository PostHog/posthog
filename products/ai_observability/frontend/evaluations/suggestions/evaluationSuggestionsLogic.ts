// The first visit starts a run that finishes within minutes, so the list reloads until its cards arrive.
const PENDING_POLL_INTERVAL_MS = 10_000

export const SUGGESTION_EXAMPLES_LIST: TraceDrawerListId = 'eval-suggestions'

export interface SuggestionInFlight {
    suggestionId: string
    action: 'accept' | 'dismiss'
}

// pinned: analytics event names and properties, renaming them breaks the suggestion experiment dashboards
export type SuggestionEvent =
    | 'llma eval suggestion shown'
    | 'llma eval suggestion examples opened'
    | 'llma eval suggestion accepted'
    | 'llma eval suggestion dismissed'

export function captureSuggestionEvent(
    event: SuggestionEvent,
    suggestion: EvalSuggestionApi,
    extra: Record<string, unknown> = {}
): void {
    posthog.capture(event, {
        suggestion_id: suggestion.id,
        kind: suggestion.kind,
        template_key: suggestion.template_key,
        ...extra,
    })
}

