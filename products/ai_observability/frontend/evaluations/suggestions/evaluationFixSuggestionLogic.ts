import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import * as api from '../../generated/api'
import type { EvalSuggestionApi } from '../../generated/api.schemas'
import { evaluationErrorMessage } from '../apiErrors'
import { llmEvaluationLogic } from '../llmEvaluationLogic'
import { llmEvaluationsLogic } from '../llmEvaluationsLogic'
import { markEvaluationsOverviewStale } from '../overview/evaluationsOverviewLogic'
import { captureSuggestionEvent, evaluationSuggestionsLogic } from './evaluationSuggestionsLogic'

export interface EvaluationFixSuggestionLogicProps {
    suggestionId: string
    evaluationId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface evaluationFixSuggestionLogicValues {
    currentTeamId: number | null // teamLogic
    applying: boolean
    openFix: EvalSuggestionApi | null
    suggestion: EvalSuggestionApi | null
    suggestionLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface evaluationFixSuggestionLogicActions {
    applyFix: () => {
        value: true
    }
    applyFixFailed: () => {
        value: true
    }
    applyFixSucceeded: (suggestion: EvalSuggestionApi) => {
        suggestion: EvalSuggestionApi
    }
    loadSuggestion: () => any
    loadSuggestionFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSuggestionSuccess: (
        suggestion: EvalSuggestionApi,
        payload?: any
    ) => {
        suggestion: EvalSuggestionApi
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface evaluationFixSuggestionLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        openFix: (suggestion: EvalSuggestionApi | null, evaluationId: string) => EvalSuggestionApi | null
    }
}

export type evaluationFixSuggestionLogicType = MakeLogicType<
    evaluationFixSuggestionLogicValues,
    evaluationFixSuggestionLogicActions,
    EvaluationFixSuggestionLogicProps,
    evaluationFixSuggestionLogicMeta
>

export const evaluationFixSuggestionLogic = kea<evaluationFixSuggestionLogicType>([
    props({} as EvaluationFixSuggestionLogicProps),
    key((props) => props.suggestionId),
    path((key) => ['products', 'ai_observability', 'evaluations', 'suggestions', 'evaluationFixSuggestionLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),

    actions({
        applyFix: true,
        applyFixSucceeded: (suggestion: EvalSuggestionApi) => ({ suggestion }),
        applyFixFailed: true,
    }),

    loaders(({ props, values }) => ({
        suggestion: [
            null as EvalSuggestionApi | null,
            {
                loadSuggestion: async () =>
                    await api.evaluationSuggestionsRetrieve(String(values.currentTeamId), props.suggestionId),
            },
        ],
    })),

    reducers({
        suggestion: {
            applyFixSucceeded: (_, { suggestion }) => suggestion,
        },
        applying: [
            false,
            {
                applyFix: () => true,
                applyFixSucceeded: () => false,
                applyFixFailed: () => false,
            },
        ],
    }),

    selectors({
        // A link copied onto another evaluation, or a fix someone already handled, shows nothing.
        openFix: [
            (s, p) => [s.suggestion, p.evaluationId],
            (suggestion: EvalSuggestionApi | null, evaluationId: string): EvalSuggestionApi | null =>
                suggestion?.status === 'proposed' &&
                suggestion.kind === 'fix_eval' &&
                suggestion.target_evaluation === evaluationId
                    ? suggestion
                    : null,
        ],
    }),

    listeners(({ actions, props, values }) => ({
        loadSuggestionSuccess: () => {
            if (values.openFix) {
                // The step that shows the filter the fix changes.
                llmEvaluationLogic.findMounted({ evaluationId: props.evaluationId })?.actions.setFormStep('traffic')
            }
        },

        applyFix: async () => {
            let fixed: EvalSuggestionApi
            try {
                fixed = await api.evaluationSuggestionsApplyFixCreate(String(values.currentTeamId), props.suggestionId)
            } catch (error) {
                lemonToast.error(evaluationErrorMessage(error, "Couldn't apply the change. Try again."))
                actions.applyFixFailed()
                return
            }
            captureSuggestionEvent('llma eval suggestion accepted', fixed)
            actions.applyFixSucceeded(fixed)
            lemonToast.success('Filter updated. The eval runs on new traffic again.')
            // The form holds the old filter, and saving it again would put that filter back.
            llmEvaluationLogic.findMounted({ evaluationId: props.evaluationId })?.actions.loadEvaluation()
            evaluationSuggestionsLogic.findMounted()?.actions.suggestionRemoved(fixed.id)
            llmEvaluationsLogic.findMounted()?.actions.loadEvaluations()
            markEvaluationsOverviewStale()
            const { location, searchParams, hashParams } = router.values
            router.actions.replace(location.pathname, { ...searchParams, suggestion: undefined }, hashParams)
        },
    })),

    afterMount(({ actions }) => {
        actions.loadSuggestion()
    }),
])
