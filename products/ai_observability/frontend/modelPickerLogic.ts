export const modelPickerLogic = kea<modelPickerLogicType>([
    path(['products', 'ai_observability', 'frontend', 'modelPickerLogic']),

    connect(() => ({
        values: [llmProviderKeysLogic, ['providerKeys', 'providerKeysLoading']],
        actions: [
            llmProviderKeysLogic,
            ['loadProviderKeysSuccess', 'createProviderKeySuccess', 'updateProviderKeySuccess'],
        ],
    })),

    actions({
        setFailedByokProviderKeyIds: (providerKeyIds: string[]) => ({ providerKeyIds }),
    }),

    loaders(({ values, actions }) => ({
        byokModels: {
            __default: [] as ModelOption[],
            loadByokModels: async (): Promise<ModelOption[]> => {
                const validKeys = values.providerKeys.filter((k: LLMProviderKey) => k.state === 'ok')
                if (validKeys.length === 0) {
                    return []
                }
                const failedProviderKeyIds: string[] = []
                const results = await Promise.all(
                    validKeys.map(async (key: LLMProviderKey) => {
                        try {
                            // nosemgrep: prefer-codegen-api
                            const rawModels = (await api.get(
                                `/api/llm_proxy/models/?provider_key_id=${encodeURIComponent(key.id)}`
                            )) as (Omit<ModelOption, 'providerKeyId' | 'isRecommended'> & {
                                is_recommended?: boolean
                            })[]
                            return rawModels.map((m) => ({
                                id: m.id,
                                name: m.name,
                                provider: m.provider,
                                description: m.description,
                                isRecommended: m.is_recommended ?? false,
                                providerKeyId: key.id,
                            }))
                        } catch {
                            failedProviderKeyIds.push(key.id)
                            return []
                        }
                    })
                )
                actions.setFailedByokProviderKeyIds(failedProviderKeyIds)
                const dedupedModels = new Map<string, ModelOption>()
                for (const models of results) {
                    for (const model of models) {
                        const dedupeKey = `${model.providerKeyId ?? ''}::${model.id}`
                        if (!dedupedModels.has(dedupeKey)) {
                            dedupedModels.set(dedupeKey, model)
                        }
                    }
                }
                return Array.from(dedupedModels.values())
            },
        },
        playgroundModels: {
            __default: [] as ModelOption[],
            loadPlaygroundModels: async (): Promise<ModelOption[]> => {
                // nosemgrep: prefer-codegen-api
                const rawModels = (await api.get('/api/llm_proxy/models/')) as (Omit<ModelOption, 'isRecommended'> & {
                    is_recommended?: boolean
                })[]
                return (rawModels ?? []).map((m) => ({
                    id: m.id,
                    name: m.name,
                    provider: m.provider,
                    description: m.description,
                    isRecommended: m.is_recommended ?? false,
                }))
            },
        },
    })),

    reducers({
        failedByokProviderKeyIds: [
            NO_FAILED_PROVIDER_KEYS,
            {
                // Keep the array identity when nothing failed, so the group list is not rebuilt.
                loadByokModels: (state: string[]) => (state.length === 0 ? state : NO_FAILED_PROVIDER_KEYS),
                setFailedByokProviderKeyIds: (state: string[], { providerKeyIds }: { providerKeyIds: string[] }) =>
                    providerKeyIds.length === 0 && state.length === 0 ? state : providerKeyIds,
            },
        ],
    }),

    listeners(({ actions }) => ({
        // Refresh BYOK models whenever provider keys change so the
        // model picker immediately reflects newly valid options.
        loadProviderKeysSuccess: () => {
            actions.loadByokModels()
        },
        createProviderKeySuccess: () => {
            actions.loadByokModels()
        },
        updateProviderKeySuccess: () => {
            actions.loadByokModels()
        },
    })),

    afterMount(({ actions, values }) => {
        actions.loadPlaygroundModels()
        if (values.providerKeys.length > 0) {
            actions.loadByokModels()
        }
    }),

    selectors({
        hasByokKeys: [
            (s) => [s.providerKeys],
            (providerKeys: LLMProviderKey[]): boolean => providerKeys.some((k) => k.state === 'ok'),
        ],
        playgroundProviderModelGroups: [
            (s) => [s.playgroundModels],
            (playgroundModels: ModelOption[]): ProviderModelGroup[] =>
                buildPlaygroundProviderModelGroups(Array.isArray(playgroundModels) ? playgroundModels : []),
        ],
        providerModelGroups: [
            (s) => [s.byokModels, s.providerKeys, s.failedByokProviderKeyIds],
            (
                byokModels: ModelOption[],
                providerKeys: LLMProviderKey[],
                failedByokProviderKeyIds: string[]
            ): ProviderModelGroup[] => {
                const byKeyId: Record<string, ModelOption[]> = {}
                for (const model of byokModels) {
                    const keyId = model.providerKeyId ?? ''
                    if (!byKeyId[keyId]) {
                        byKeyId[keyId] = []
                    }
                    byKeyId[keyId].push(model)
                }

                const keysPerProvider: Record<string, number> = {}
                for (const key of providerKeys) {
                    keysPerProvider[key.provider] = (keysPerProvider[key.provider] ?? 0) + 1
                }

                const failedKeyIds = new Set(failedByokProviderKeyIds)
                const groups: ProviderModelGroup[] = []
                for (const key of providerKeys) {
                    const models = byKeyId[key.id] ?? []
                    const groupLabel = (suffix: string): string =>
                        (keysPerProvider[key.provider] ?? 0) > 1
                            ? `${providerLabel(key.provider)} (${key.name})${suffix}`
                            : `${providerLabel(key.provider)}${suffix}`

                    if (models.length === 0) {
                        // A key that cannot serve models stays listed, so the picker shows why it is short.
                        if (isUnhealthyProviderKeyState(key.state)) {
                            groups.push({
                                provider: key.provider,
                                providerKeyId: key.id,
                                label: groupLabel(providerKeyStateSuffix(key.state)),
                                models: [],
                                disabledReason: UNHEALTHY_KEY_REASON,
                            })
                        } else if (failedKeyIds.has(key.id)) {
                            groups.push({
                                provider: key.provider,
                                providerKeyId: key.id,
                                label: groupLabel(UNAVAILABLE_KEY_SUFFIX),
                                models: [],
                                disabledReason: UNAVAILABLE_KEY_REASON,
                            })
                        }
                        continue
                    }

                    groups.push({
                        provider: key.provider,
                        providerKeyId: key.id,
                        label: groupLabel(''),
                        models,
                    })
                }

                return groups.sort((a, b) => {
                    const providerDiff = providerSortIndex(a.provider) - providerSortIndex(b.provider)
                    if (providerDiff !== 0) {
                        return providerDiff
                    }
                    return a.label.localeCompare(b.label)
                })
            },
        ],
    }),
])
