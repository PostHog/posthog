export const datasetItemModalLogic = kea<datasetItemModalLogicType>([
    path(['scenes', 'ai-observability', 'datasetItemModalLogic']),

    props({ datasetId: '', partialDatasetItem: null, closeModal: () => {} } as DatasetItemModalLogicProps),

    key(
        ({ datasetId, partialDatasetItem }) =>
            `dataset-item-${datasetId}-${isStoredDatasetItem(partialDatasetItem) ? partialDatasetItem.id : 'new'}`
    ),

    actions({
        setShouldCloseModal: (shouldCloseModal: boolean) => ({ shouldCloseModal }),
        setRefetchDatasetItems: (refetchDatasetItems: boolean) => ({ refetchDatasetItems }),
        setDatasetItemFormAccess: (readOnly: boolean, restoringVersion: number | null) => ({
            readOnly,
            restoringVersion,
        }),
    }),

    reducers(({ props }) => ({
        shouldCloseModal: [
            true as boolean,
            {
                setShouldCloseModal: (_, { shouldCloseModal }) => shouldCloseModal,
            },
        ],

        refetchDatasetItems: [
            false as boolean,
            {
                setRefetchDatasetItems: (_, { refetchDatasetItems }) => refetchDatasetItems,
            },
        ],

        datasetItemFormAccess: [
            {
                readOnly: !!props.readOnly,
                restoringVersion: props.restoringVersion ?? null,
            } as DatasetItemFormAccess,
            {
                setDatasetItemFormAccess: (_, { readOnly, restoringVersion }) => ({ readOnly, restoringVersion }),
            },
        ],
    })),

    forms(({ props, actions, values }) => ({
        datasetItemForm: {
            defaults: FORM_DEFAULT_VALUE as DatasetItemFormValues,

            errors: ({ input, expectedOutput, metadata }) => ({
                input: !isStringJsonValue(input, false) ? 'Input must contain a non-null JSON value' : undefined,
                expectedOutput: !isStringJsonValue(expectedOutput)
                    ? 'Expected output must contain a valid JSON value or be empty'
                    : undefined,
                metadata: !isStringJsonObject(metadata) ? 'Metadata must contain a valid JSON object' : undefined,
            }),

            submit: async (formValues) => {
                if (values.isDatasetItemFormReadOnly) {
                    return
                }
                try {
                    if (!isStoredDatasetItem(props.partialDatasetItem)) {
                        await datasetsApi.createItem({
                            dataset: props.datasetId,
                            client_item_id: props.partialDatasetItem?.client_item_id,
                            input: parseJsonValue(formValues.input) ?? {},
                            expected_output: parseJsonValue(formValues.expectedOutput),
                            source_output: props.partialDatasetItem?.source_output,
                            metadata: parseJsonObject(formValues.metadata),
                            source_trace_id: props.partialDatasetItem?.source_trace_id,
                            source_event_id: props.partialDatasetItem?.source_event_id,
                            source_timestamp: props.partialDatasetItem?.source_timestamp,
                        })
                        lemonToast.success('Dataset item created successfully')
                        if (values.shouldCloseModal) {
                            props.closeModal(true)
                        } else {
                            actions.setRefetchDatasetItems(true)
                            // In case of "save and add another", we want to reset the form values.
                            actions.setDatasetItemFormValues(FORM_DEFAULT_VALUE)
                        }
                        actions.setShouldCloseModal(true)
                    } else {
                        const updatedItem = await datasetsApi.updateItem(props.partialDatasetItem.id, {
                            base_version: props.partialDatasetItem.version,
                            input: parseJsonValue(formValues.input) ?? {},
                            expected_output: parseJsonValue(formValues.expectedOutput),
                            metadata: parseJsonObject(formValues.metadata),
                        })
                        lemonToast.success('Dataset item updated successfully')
                        props.closeModal(true)
                        actions.setDatasetItemFormValues(getDatasetItemFormDefaults(updatedItem))
                    }
                } catch (error) {
                    if (error instanceof ApiError && error.code === CodeEnumApi.StaleVersion) {
                        lemonToast.error(
                            error.detail || 'This dataset item changed after it was loaded. Reload it and try again.',
                            {
                                button: {
                                    label: 'Reload items',
                                    action: () => props.closeModal(true),
                                },
                            }
                        )
                        return
                    }

                    lemonToast.error(
                        error instanceof ApiError && error.detail
                            ? error.detail
                            : "Couldn't save dataset item. Try again."
                    )
                }
            },
        },
    })),

    selectors({
        isDatasetItemFormReadOnly: [
            (s) => [s.datasetItemFormAccess],
            ({ readOnly, restoringVersion }: DatasetItemFormAccess): boolean => readOnly || restoringVersion != null,
        ],

        datasetItemFormSubmitDisabledReason: [
            (s) => [s.datasetItemFormAccess],
            ({ restoringVersion }: DatasetItemFormAccess): string | undefined =>
                restoringVersion != null ? 'Wait for the version to finish restoring' : undefined,
        ],

        datasetItemVersionRestoreDisabledReason: [
            (s) => [s.datasetItemFormChanged, s.isDatasetItemFormSubmitting],
            (formChanged: boolean, formSubmitting: boolean): string | undefined =>
                formSubmitting
                    ? 'Wait for the item to finish saving'
                    : formChanged
                      ? 'Save or discard your changes before restoring a version'
                      : undefined,
        ],
    }),

    defaults(({ props }): { datasetItemForm: DatasetItemFormValues } => {
        return {
            datasetItemForm: props.partialDatasetItem
                ? getDatasetItemFormDefaults(props.partialDatasetItem)
                : FORM_DEFAULT_VALUE,
        }
    }),

    propsChanged(({ props, actions }, oldProps) => {
        if (props.readOnly !== oldProps.readOnly || props.restoringVersion !== oldProps.restoringVersion) {
            actions.setDatasetItemFormAccess(!!props.readOnly, props.restoringVersion ?? null)
        }

        const modalOpened = props.isModalOpen && !oldProps.isModalOpen
        const itemChanged = props.partialDatasetItem !== oldProps.partialDatasetItem
        if (!props.isModalOpen || (!modalOpened && !itemChanged)) {
            return
        }

        actions.setRefetchDatasetItems(false)
        actions.resetDatasetItemForm(
            props.partialDatasetItem ? getDatasetItemFormDefaults(props.partialDatasetItem) : FORM_DEFAULT_VALUE
        )
    }),
])

export function isStoredDatasetItem(item?: DatasetItemModalValue | null): item is DatasetItemReadApi {
    return !!item && 'id' in item
}

function getDatasetItemFormDefaults(partialDatasetItem: DatasetItemModalValue): DatasetItemFormValues {
    return {
        input: prettifyJson(partialDatasetItem.input) || EMPTY_JSON,
        expectedOutput: prettifyJson(partialDatasetItem.expected_output) || '',
        metadata: prettifyJson(partialDatasetItem.metadata) || EMPTY_JSON,
    }
}
