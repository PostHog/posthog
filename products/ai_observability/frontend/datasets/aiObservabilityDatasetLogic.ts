export const aiObservabilityDatasetLogic = kea<aiObservabilityDatasetLogicType>([
    path(['scenes', 'ai-observability', 'aiObservabilityDatasetLogic']),

    props({ datasetId: 'new' } as DatasetLogicProps),

    key(({ datasetId }) => `dataset-${datasetId}`),

    connect(() => ({
        actions: [teamLogic, ['addProductIntent']],
    })),

    actions({
        setDataset: (dataset: DatasetReadApi | DatasetFormValues) => ({ dataset }),
        editDataset: (editing: boolean) => ({ editing }),
        archiveDataset: true,
        setActiveTab: (tab: DatasetTab) => ({ tab }),
        // beforeUnmount doesn't work as expected for scenes.
        onUnmount: true,
        setFilters: (filters: Partial<DatasetItemsFilters>, debounce: boolean = true) => ({ filters, debounce }),
        archiveDatasetItem: (itemId: string, baseVersion: number) => ({ itemId, baseVersion }),
        triggerDatasetItemModal: (open: boolean) => ({ open }),
        setSelectedDatasetItem: (datasetItem: DatasetItemReadApi) => ({ datasetItem }),
        closeModalAndRefetchDatasetItems: (refetchDatasetItems?: boolean) => ({ refetchDatasetItems }),
        setArchivingDataset: (archiving: boolean) => ({ archiving }),
        setArchivingDatasetItemId: (itemId: string | null) => ({ itemId }),
    }),

    reducers({
        dataset: [
            null as DatasetReadApi | DatasetFormValues | null,
            {
                loadDatasetSuccess: (_, { dataset }) => dataset,
                setDataset: (_, { dataset }) => dataset,
            },
        ],

        isEditingDataset: [
            false as boolean,
            {
                editDataset: (_, { editing }) => editing,
            },
        ],

        activeTab: [
            DatasetTab.Items as DatasetTab,
            {
                setActiveTab: (_, { tab }) => tab,
            },
        ],

        rawFilters: [
            null as Partial<DatasetItemsFilters> | null,
            {
                setFilters: (state, { filters }) =>
                    cleanFilters({
                        ...state,
                        ...filters,
                        // Reset page on filter change except if it's page that's being updated
                        ...('page' in filters ? {} : { page: 1 }),
                    }),
            },
        ],

        isDatasetItemModalOpen: [
            false as boolean,
            {
                triggerDatasetItemModal: (_, { open }) => open,
                closeModalAndRefetchDatasetItems: () => false,
            },
        ],

        selectedDatasetItem: [
            null as DatasetItemReadApi | null,
            {
                setSelectedDatasetItem: (_, { datasetItem }) => datasetItem,
                // Reset the selected dataset item when the modal is closed
                triggerDatasetItemModal: (state, { open }) => (open ? state : null),
                closeModalAndRefetchDatasetItems: () => null,
            },
        ],

        isArchivingDataset: [
            false as boolean,
            {
                setArchivingDataset: (_, { archiving }) => archiving,
                archiveDataset: () => true,
            },
        ],

        archivingDatasetItemId: [
            null as string | null,
            {
                archiveDatasetItem: (_, { itemId }) => itemId,
                setArchivingDatasetItemId: (_, { itemId }) => itemId,
            },
        ],
    }),

    loaders(({ props, values }) => ({
        dataset: {
            __default: null as DatasetReadApi | DatasetFormValues | null,
            loadDataset: () => {
                return datasetsApi.getDataset(props.datasetId)
            },
        },

        datasetItems: [
            { results: [], count: 0 } as PaginatedDatasetItemReadListApi,
            {
                loadDatasetItems: async (debounce: boolean = false, breakpoint) => {
                    if (debounce && values.datasetItems.results.length > 0) {
                        await breakpoint(300)
                    }

                    const { filters } = values

                    // Scroll to top if the page changed, except if changed via back/forward
                    if (
                        sceneLogic.findMounted()?.values.activeSceneId === 'AIObservabilityDataset' &&
                        router.values.lastMethod !== 'POP' &&
                        values.datasetItems.results.length > 0 &&
                        values.rawFilters?.page !== filters.page
                    ) {
                        window.scrollTo(0, 0)
                    }

                    const response = await datasetsApi.listItems({
                        dataset: props.datasetId,
                        offset: Math.max(0, (filters.page - 1) * DATASET_ITEMS_PER_PAGE),
                        limit: DATASET_ITEMS_PER_PAGE,
                    })
                    return response
                },
            },
        ],
    })),

    forms(({ actions, props }) => ({
        datasetForm: {
            defaults: { name: '', description: '', metadata: '' } as DatasetFormValues,

            errors: ({ name, metadata }) => ({
                name: !name?.trim() ? 'Dataset name is required' : undefined,
                metadata: !isStringJsonObject(metadata)
                    ? 'Dataset metadata must contain a valid JSON object or be empty'
                    : undefined,
            }),

            submit: async (formValues) => {
                const isNew = props.datasetId === 'new'
                try {
                    let savedDataset: DatasetReadApi
                    if (isNew) {
                        savedDataset = await datasetsApi.createDataset({
                            name: formValues.name,
                            description: formValues.description,
                            metadata: parseJsonObject(formValues.metadata),
                        })
                        lemonToast.success('Dataset created successfully')
                        router.actions.replace(urls.aiObservabilityDataset(savedDataset.id))

                        void actions.addProductIntent({
                            product_type: ProductKey.LLM_DATASETS,
                            intent_context: ProductIntentContext.LLM_DATASET_CREATED,
                        })
                    } else {
                        savedDataset = await datasetsApi.updateDataset(props.datasetId, {
                            ...formValues,
                            metadata: parseJsonObject(formValues.metadata),
                        })
                        lemonToast.success('Dataset updated successfully')
                    }
                    aiObservabilityDatasetsLogic.findMounted()?.actions.loadDatasets(false)
                    actions.setDataset(savedDataset)
                    actions.editDataset(false)
                    actions.setDatasetFormValues(getDatasetFormDefaults(savedDataset))
                } catch (error: any) {
                    const message = error?.detail || 'Failed to save dataset'
                    lemonToast.error(message)
                    throw error
                }
            },
        },
    })),

    selectors({
        isNewDataset: [() => [(_, props) => props], (props) => props.datasetId === 'new'],

        isDatasetMissing: [
            (s) => [s.dataset, s.datasetLoading],
            (dataset: DatasetReadApi | DatasetFormValues | null, datasetLoading: boolean) =>
                !datasetLoading && dataset === null,
        ],

        shouldDisplaySkeleton: [
            (s) => [s.dataset, s.datasetLoading],
            (dataset: DatasetReadApi | DatasetFormValues | null, datasetLoading: boolean) => !dataset && datasetLoading,
        ],

        filters: [
            (s) => [s.rawFilters],
            (rawFilters: Partial<DatasetItemsFilters> | null): DatasetItemsFilters => cleanFilters(rawFilters || {}),
        ],

        datasetItemsCount: [
            (s) => [s.datasetItems],
            (datasetItems: PaginatedDatasetItemReadListApi) => datasetItems.count,
        ],

        pagination: [
            (s) => [s.filters, s.datasetItemsCount],
            (filters: DatasetItemsFilters, count: number): PaginationManual => ({
                controlled: true,
                pageSize: filters.limit,
                currentPage: filters.page,
                entryCount: count,
            }),
        ],

        breadcrumbs: [
            (s) => [s.dataset, router.selectors.searchParams],
            (dataset: DatasetReadApi | DatasetFormValues | null, searchParams: Record<string, any>): Breadcrumb[] => [
                {
                    name: 'Datasets',
                    path: combineUrl(urls.aiObservabilityDatasets(), searchParams).url,
                    key: 'AIObservabilityDatasets',
                    iconType: 'llm_datasets',
                },
                {
                    name: dataset && 'name' in dataset ? dataset.name : 'New Dataset',
                    key: 'AIObservabilityDataset',
                    iconType: 'llm_datasets',
                },
            ],
        ],
    }),

    listeners(({ actions, props, values, selectors, asyncActions }) => ({
        archiveDataset: async () => {
            if (props.datasetId !== 'new') {
                try {
                    await datasetsApi.archiveDataset(props.datasetId)
                    const datasetName = values.dataset?.name || 'Dataset'
                    lemonToast.info(`${datasetName} has been archived.`, {
                        button: {
                            label: 'Undo',
                            dataAttr: 'undo-archive-dataset',
                            action: async () => {
                                try {
                                    await datasetsApi.restoreDataset(props.datasetId)
                                    aiObservabilityDatasetsLogic.findMounted()?.actions.loadDatasets(false)
                                    lemonToast.success(`${datasetName} has been restored.`)
                                } catch {
                                    lemonToast.error("Couldn't restore dataset. Try again.")
                                }
                            },
                        },
                    })
                    router.actions.replace(urls.aiObservabilityDatasets(), router.values.searchParams)
                } catch {
                    lemonToast.error("Couldn't archive dataset. Try again.")
                }
                actions.setArchivingDataset(false)
            }
        },

        onUnmount: () => {
            if (props.datasetId === 'new') {
                // Reset form values when creating a new dataset
                actions.setDatasetFormValues(DEFAULT_DATASET_FORM_VALUES)
            } else {
                // Set form values when editing an existing dataset
                const existingDataset = findExistingDataset(props.datasetId)
                if (existingDataset) {
                    actions.setDatasetFormValues(getDatasetFormDefaults(existingDataset))
                } else {
                    actions.setDatasetFormValues(DEFAULT_DATASET_FORM_VALUES)
                }
            }
        },

        archiveDatasetItem: async ({ itemId, baseVersion }) => {
            try {
                if (props.datasetId !== 'new') {
                    const archivedItem = await datasetsApi.archiveItem(itemId, { base_version: baseVersion })
                    lemonToast.info(`Dataset item ${truncateValue(itemId)} has been archived.`, {
                        button: {
                            label: 'Undo',
                            dataAttr: 'undo-archive-dataset-item',
                            action: async () => {
                                try {
                                    await datasetsApi.restoreItem(itemId, { base_version: archivedItem.version })
                                    await asyncActions.loadDatasetItems(false)
                                } catch (error) {
                                    showDatasetItemMutationError(
                                        error,
                                        "Couldn't restore dataset item. Refresh the dataset and try again.",
                                        () => {
                                            void asyncActions.loadDatasetItems(false)
                                        }
                                    )
                                }
                            },
                        },
                    })
                    await asyncActions.loadDatasetItems(false)
                }
            } catch (error) {
                showDatasetItemMutationError(
                    error,
                    "Couldn't archive dataset item. Refresh the dataset and try again.",
                    () => {
                        void asyncActions.loadDatasetItems(false)
                    }
                )
            } finally {
                actions.setArchivingDatasetItemId(null)
            }
        },

        loadDatasetSuccess: ({ dataset }) => {
            if (!values.isEditingDataset) {
                // Set form defaults when dataset is loaded
                actions.setDatasetFormValues(getDatasetFormDefaults(dataset))
            }
        },

        loadDatasetItemsSuccess: ({ datasetItems }) => {
            if (router.values.searchParams.item) {
                const item = datasetItems.results.find((item) => item.id === router.values.searchParams.item)
                if (item && values.selectedDatasetItem !== item) {
                    actions.setSelectedDatasetItem(item)
                    actions.triggerDatasetItemModal(true)
                }
            }
        },

        setFilters: async ({ debounce }, _, __, previousState) => {
            const oldFilters = selectors.filters(previousState)
            const { filters } = values

            if (!objectsEqual(oldFilters, filters)) {
                await asyncActions.loadDatasetItems(debounce)
            }
        },

        setActiveTab: ({ tab }) => {
            if (tab === DatasetTab.Items && props.datasetId !== 'new') {
                actions.loadDatasetItems(true)
            }
        },

        closeModalAndRefetchDatasetItems: ({ refetchDatasetItems }) => {
            if (refetchDatasetItems) {
                actions.loadDatasetItems()
            }
        },
    })),

    urlToAction(({ actions, values }) => ({
        [urls.aiObservabilityDataset(':id')]: (_, searchParams) => {
            if (
                searchParams.tab &&
                Object.values(DatasetTab).includes(searchParams.tab as DatasetTab) &&
                searchParams.tab !== values.activeTab
            ) {
                actions.setActiveTab(searchParams.tab as DatasetTab)
            }

            const newFilters = cleanFilters(searchParams)
            if (!objectsEqual(values.filters, newFilters)) {
                actions.setFilters(newFilters, false)
            }

            // Open the dataset item modal if the item is set in the URL
            if (searchParams.item) {
                const item = values.datasetItems.results.find((item) => item.id === searchParams.item)
                if (item) {
                    actions.setSelectedDatasetItem(item)
                    actions.triggerDatasetItemModal(true)
                }
            }
        },
    })),

    trackedActionToUrl(({ values }) => ({
        closeModalAndRefetchDatasetItems: () => {
            const nextSearchParams = { ...router.values.searchParams, item: undefined }
            return [
                urls.aiObservabilityDataset(isDataset(values.dataset) ? values.dataset.id : 'new'),
                nextSearchParams,
                {},
                { replace: false },
            ]
        },
    })),

    // TRICKY: Order matters here. Keep it in the bottom.
    defaults(
        ({
            props,
        }): {
            dataset: DatasetFormValues | DatasetReadApi | null
            datasetForm: DatasetFormValues
        } => {
            if (props.datasetId === 'new') {
                return {
                    dataset: DEFAULT_DATASET_FORM_VALUES,
                    datasetForm: DEFAULT_DATASET_FORM_VALUES,
                }
            }

            // Don't show a loader if the dataset has already been loaded.
            const existingDataset = findExistingDataset(props.datasetId)
            if (existingDataset) {
                return {
                    dataset: existingDataset,
                    datasetForm: getDatasetFormDefaults(existingDataset),
                }
            }

            return {
                dataset: null,
                datasetForm: DEFAULT_DATASET_FORM_VALUES,
            }
        }
    ),

    // TRICKY: Order matters here. Keep it in the bottom.
    afterMount(({ actions, values }) => {
        // Load dataset in any case, as it might be stale.
        if (!values.isNewDataset) {
            actions.loadDataset()
            actions.loadDatasetItems()
        }
    }),
])

const DEFAULT_DATASET_FORM_VALUES: DatasetFormValues = {
    name: '',
    description: '',
    metadata: '{\n  \n}',
}

/**
 * Get default form values for a dataset.
 * @param dataset - The dataset to get the default form values for
 * @returns The default form values
 */
function getDatasetFormDefaults(dataset: DatasetReadApi): DatasetFormValues {
    return {
        name: dataset.name,
        description: dataset.description || '',
        metadata: prettifyJson(dataset.metadata) || EMPTY_JSON,
    }
}

/**
 * Find an existing dataset in the datasets logic.
 * @param datasetId - The ID of the dataset to find
 * @returns The dataset if found, undefined otherwise
 */
function findExistingDataset(datasetId: string): DatasetReadApi | undefined {
    return aiObservabilityDatasetsLogic
        .findMounted()
        ?.values.datasets.results.find((dataset) => dataset.id === datasetId)
}
