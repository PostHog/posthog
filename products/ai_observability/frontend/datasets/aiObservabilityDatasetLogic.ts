export interface DatasetItemsFilters {
    page: number
    limit: number
    archived: boolean
    revision: number | null
}

type DatasetExportErrorOperation = 'create' | 'status' | null

export const DATASET_ITEMS_PER_PAGE = 25

export function isDataset(dataset: DatasetReadApi | DatasetFormValues | null): dataset is DatasetReadApi {
    return dataset !== null && 'id' in dataset
}

function cleanFilters(values: Partial<DatasetItemsFilters> & { item_status?: unknown }): DatasetItemsFilters {
    const revision = Number(values.revision)
    return {
        page: parseInt(String(values.page)) || 1,
        limit: parseInt(String(values.limit)) || DATASET_ITEMS_PER_PAGE,
        archived: values.item_status ? values.item_status === 'archived' : values.archived === true,
        revision: Number.isInteger(revision) && revision > 0 ? revision : null,
    }
}

function showDatasetItemMutationError(error: unknown, fallbackMessage: string, reloadItems: () => void): void {
    if (error instanceof ApiError && error.code === CodeEnumApi.StaleVersion) {
        lemonToast.error(error.detail || 'This dataset item changed after it was loaded. Reload it and try again.', {
            button: {
                label: 'Reload items',
                action: reloadItems,
            },
        })
        return
    }
    lemonToast.error(error instanceof ApiError && error.detail ? error.detail : fallbackMessage)
}

