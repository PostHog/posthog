export const aiObservabilityDatasetsLogic = kea<aiObservabilityDatasetsLogicType>([
    path(['scenes', 'ai-observability', 'aiObservabilityDatasetsLogic']),
    props({} as AIObservabilityDatasetsLogicProps),

    actions({
        setFilters: (filters: Partial<DatasetFilters>, merge: boolean = true, debounce: boolean = true) => ({
            filters,
            merge,
            debounce,
        }),
        loadDatasets: (debounce: boolean = true) => ({ debounce }),
        archiveDataset: (datasetId: string) => ({ datasetId }),
        restoreDataset: (datasetId: string) => ({ datasetId }),
        setArchivingDatasetId: (datasetId: string | null) => ({ datasetId }),
    }),

    reducers({
        archivingDatasetId: [
            null as string | null,
            {
                archiveDataset: (_, { datasetId }) => datasetId,
                restoreDataset: (_, { datasetId }) => datasetId,
                setArchivingDatasetId: (_, { datasetId }) => datasetId,
            },
        ],
        rawFilters: [
            null as Partial<DatasetFilters> | null,
            {
                setFilters: (state, { filters, merge }) =>
                    cleanFilters({
                        ...(merge ? state || {} : {}),
                        ...filters,
                        // Reset page on filter change except if it's page that's being updated
                        ...('page' in filters ? {} : { page: 1 }),
                    }),
            },
        ],
    }),

    loaders(({ values }) => ({
        datasets: [
            { results: [], count: 0 } as PaginatedDatasetReadListApi,
            {
                loadDatasets: async ({ debounce }, breakpoint) => {
                    if (debounce && values.datasets.results.length > 0) {
                        await breakpoint(300)
                    }

                    const { filters } = values
                    const params = {
                        search: filters.search || undefined,
                        order_by: filters.order_by,
                        offset: Math.max(0, (filters.page - 1) * DATASETS_PER_PAGE),
                        limit: DATASETS_PER_PAGE,
                        archived: filters.archived,
                    }

                    // Scroll to top if the page changed, except if changed via back/forward
                    if (
                        sceneLogic.findMounted()?.values.activeSceneId === 'AIObservabilityDatasets' &&
                        router.values.lastMethod !== 'POP' &&
                        values.datasets.results.length > 0 &&
                        values.rawFilters?.page !== filters.page
                    ) {
                        window.scrollTo(0, 0)
                    }

                    const response = await datasetsApi.listDatasets(params)
                    return response
                },
            },
        ],
    })),

    selectors({
        filters: [
            (s) => [s.rawFilters],
            (rawFilters: Partial<DatasetFilters> | null): DatasetFilters => cleanFilters(rawFilters || {}),
        ],

        count: [(s) => [s.datasets], (datasets: PaginatedDatasetReadListApi) => datasets.count],

        sorting: [
            (s) => [s.filters],
            (filters: DatasetFilters): Sorting | null => {
                if (!filters.order_by) {
                    return {
                        columnKey: 'updated_at',
                        order: -1,
                    }
                }
                return filters.order_by.startsWith('-')
                    ? {
                          columnKey: filters.order_by.slice(1),
                          order: -1,
                      }
                    : {
                          columnKey: filters.order_by,
                          order: 1,
                      }
            },
        ],

        pagination: [
            (s) => [s.filters, s.count],
            (filters: DatasetFilters, count: number): PaginationManual => ({
                controlled: true,
                pageSize: DATASETS_PER_PAGE,
                currentPage: filters.page,
                entryCount: count,
            }),
        ],

        datasetCountLabel: [
            (s) => [s.filters, s.count],
            (filters: DatasetFilters, count: number) => {
                const start = (filters.page - 1) * DATASETS_PER_PAGE + 1
                const end = Math.min(filters.page * DATASETS_PER_PAGE, count)

                return count === 0 ? '0 datasets' : `${start}-${end} of ${pluralize(count, 'dataset')}`
            },
        ],
    }),

    listeners(({ actions, asyncActions, values, selectors }) => ({
        setFilters: async ({ debounce }, _, __, previousState) => {
            const oldFilters = selectors.filters(previousState)
            const { filters } = values

            if (!objectsEqual(oldFilters, filters)) {
                await asyncActions.loadDatasets(debounce)
            }
        },

        archiveDataset: async ({ datasetId }) => {
            try {
                const datasetName = values.datasets.results.find((dataset) => dataset.id === datasetId)?.name
                await datasetsApi.archiveDataset(datasetId)
                lemonToast.info(`${datasetName || 'Dataset'} has been archived.`, {
                    button: {
                        label: 'Undo',
                        dataAttr: 'undo-archive-dataset',
                        action: async () => {
                            try {
                                await datasetsApi.restoreDataset(datasetId)
                                await asyncActions.loadDatasets(false)
                                lemonToast.success(`${datasetName || 'Dataset'} has been restored.`)
                            } catch {
                                lemonToast.error("Couldn't restore dataset. Try again.")
                            }
                        },
                    },
                })
                await asyncActions.loadDatasets(false)
            } catch {
                lemonToast.error("Couldn't archive dataset. Try again.")
            } finally {
                actions.setArchivingDatasetId(null)
            }
        },

        restoreDataset: async ({ datasetId }) => {
            try {
                const datasetName = values.datasets.results.find((dataset) => dataset.id === datasetId)?.name
                await datasetsApi.restoreDataset(datasetId)
                await asyncActions.loadDatasets(false)
                lemonToast.success(`${datasetName || 'Dataset'} has been unarchived.`)
            } catch {
                lemonToast.error("Couldn't unarchive dataset. Try again.")
            } finally {
                actions.setArchivingDatasetId(null)
            }
        },
    })),

    trackedActionToUrl(({ values }) => {
        const changeUrl = ():
            | [
                  string,
                  Record<string, any>,
                  Record<string, any>,
                  {
                      replace: boolean
                  },
              ]
            | void => {
            const { page, ...pagedSearchOrderParams } = cleanPagedSearchOrderParams(values.filters)
            const nextValues = {
                ...pagedSearchOrderParams,
                datasets_page: page,
                dataset_status: values.filters.archived ? 'archived' : undefined,
            }
            const urlValues = cleanFilters(router.values.searchParams)
            if (!objectsEqual(values.filters, urlValues)) {
                return [urls.aiObservabilityDatasets(), nextValues, {}, { replace: true }]
            }
        }
        return {
            setFilters: changeUrl,
        }
    }),

    urlToAction(({ actions, values }) => ({
        [urls.aiObservabilityDatasets()]: (_, searchParams, __, { method }) => {
            const newFilters = cleanFilters(searchParams)
            if (!objectsEqual(values.filters, newFilters)) {
                actions.setFilters(newFilters, false)
            } else if (method !== 'REPLACE') {
                actions.loadDatasets(false)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadDatasets()
    }),
])
