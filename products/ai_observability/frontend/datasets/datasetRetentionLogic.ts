export type datasetRetentionLogicType = MakeLogicType<
    datasetRetentionLogicValues,
    datasetRetentionLogicActions,
    Record<string, any>,
    datasetRetentionLogicMeta
>

export const datasetRetentionLogic = kea<datasetRetentionLogicType>([
    path(['products', 'ai_observability', 'frontend', 'datasets', 'datasetRetentionLogic']),
    actions({
        setExpanded: (expanded: boolean) => ({ expanded }),
        setKind: (kind: DatasetsRetentionRetrieveKind) => ({ kind }),
        setPage: (page: number) => ({ page }),
        loadRetention: true,
        refreshRetention: true,
        reportOpen: (entry: DatasetRetentionEntryApi) => ({ entry }),
    }),
    loaders(({ values }) => ({
        retention: [
            null as DatasetRetentionReadApi | null,
            {
                loadRetention: async (_, breakpoint) => {
                    try {
                        return await datasetsApi.getRetention({
                            kind: values.kind,
                            limit: RETENTION_PAGE_SIZE,
                            offset: (values.page - 1) * RETENTION_PAGE_SIZE,
                        })
                    } finally {
                        breakpoint()
                    }
                },
            },
        ],
        extendedEntry: [
            null as DatasetRetentionEntryApi | null,
            {
                extendRetention: async (entry: DatasetRetentionEntryApi, breakpoint) => {
                    try {
                        return await datasetsApi.extendRetention(entry.dataset_id, entry.revision ?? undefined)
                    } finally {
                        breakpoint()
                    }
                },
            },
        ],
    })),
    reducers({
        expanded: [false, { setExpanded: (_, { expanded }) => expanded }],
        kind: ['datasets' as DatasetsRetentionRetrieveKind, { setKind: (_, { kind }) => kind }],
        page: [1, { setPage: (_, { page }) => page, setKind: () => 1 }],
        retentionError: [
            false,
            { loadRetention: () => false, loadRetentionFailure: () => true, loadRetentionSuccess: () => false },
        ],
        extendingKey: [
            null as string | null,
            {
                extendRetention: (_, entry) => `${entry.dataset_id}:${entry.revision ?? 'latest'}`,
                extendRetentionSuccess: () => null,
                extendRetentionFailure: () => null,
            },
        ],
    }),
    selectors({
        warning: [
            (s) => [s.retention],
            (retention: DatasetRetentionReadApi | null): string => {
                if (!retention) {
                    return ''
                }
                const parts = []
                if (retention.datasets_count) {
                    parts.push(`${retention.datasets_count} ${retention.datasets_count === 1 ? 'dataset' : 'datasets'}`)
                }
                if (retention.revisions_count) {
                    parts.push(
                        `${retention.revisions_count} older ${retention.revisions_count === 1 ? 'revision' : 'revisions'}`
                    )
                }
                return parts.length ? `${parts.join(' and ')} expiring within 7 days` : ''
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        refreshRetention: async (_, breakpoint) => {
            await breakpoint(100)
            actions.loadRetention()
        },
        [aiObservabilityDatasetsLogic.actionTypes.datasetRetentionChanged]: () => actions.refreshRetention(),
        setKind: () => actions.loadRetention(),
        setPage: () => actions.loadRetention(),
        setExpanded: ({ expanded }) => {
            if (expanded) {
                actions.loadRetention()
                posthog.capture('llma dataset retention reviewed')
            }
        },
        loadRetentionSuccess: ({ retention }) => {
            if (retention.datasets_count + retention.revisions_count > 0 && !cache.reportedWarning) {
                cache.reportedWarning = true
                posthog.capture('llma dataset retention warning viewed', {
                    datasets_count: retention.datasets_count,
                    revisions_count: retention.revisions_count,
                })
            }
            const otherCount = values.kind === 'datasets' ? retention.revisions_count : retention.datasets_count
            if (retention.count === 0 && otherCount > 0) {
                actions.setKind(values.kind === 'datasets' ? 'revisions' : 'datasets')
            } else if (values.page > Math.max(1, Math.ceil(retention.count / RETENTION_PAGE_SIZE))) {
                actions.setPage(Math.max(1, Math.ceil(retention.count / RETENTION_PAGE_SIZE)))
            }
        },
        extendRetentionSuccess: ({ extendedEntry }) => {
            lemonToast.success(
                createElement(
                    'span',
                    null,
                    createElement(
                        'span',
                        null,
                        extendedEntry.revision !== null
                            ? `Revision ${extendedEntry.revision} retention extended`
                            : 'Dataset retention extended'
                    ),
                    extendedEntry.expires_at &&
                        createElement(
                            'span',
                            null,
                            ' until ',
                            createElement(TZLabel, { time: extendedEntry.expires_at, timestampStyle: 'absolute' })
                        ),
                    createElement(
                        'span',
                        null,
                        extendedEntry.revision !== null
                            ? '. Its dataset was refreshed too.'
                            : '. Older revisions keep their own deadlines.'
                    )
                )
            )
            actions.loadRetention()
            aiObservabilityDatasetsLogic.findMounted()?.actions.loadDatasets(false)
        },
        extendRetentionFailure: () => {
            lemonToast.error("Couldn't extend retention. Refresh the list and try again.")
            posthog.capture('llma dataset retention extension failed')
            actions.loadRetention()
        },
        reportOpen: ({ entry }) => {
            posthog.capture('llma dataset retention opened', {
                dataset_id: entry.dataset_id,
                revision: entry.revision,
            })
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.disposables.add(() => {
            actions.refreshRetention()
            window.addEventListener('focus', actions.refreshRetention)
            return () => window.removeEventListener('focus', actions.refreshRetention)
        })
    }),
])
