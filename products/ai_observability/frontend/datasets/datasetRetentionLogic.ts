import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'
import { createElement } from 'react'

import { TZLabel } from 'lib/components/TZLabel'
import { lemonToast } from 'lib/lemon-ui/LemonToast'

import type {
    DatasetRetentionEntryApi,
    DatasetRetentionReadApi,
    DatasetsRetentionRetrieveKind,
} from '../generated/api.schemas'
import { aiObservabilityDatasetsLogic } from './aiObservabilityDatasetsLogic'
import { datasetsApi } from './datasetsApi'

export const RETENTION_PAGE_SIZE = 5

