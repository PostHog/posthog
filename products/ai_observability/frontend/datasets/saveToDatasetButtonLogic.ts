export const saveToDatasetButtonLogic = kea<saveToDatasetButtonLogicType>([
    path(['scenes', 'ai-observability', 'saveToDatasetButtonLogic']),

    props({ step: null } as saveToDatasetButtonLogicProps),

    actions({
        setIsModalOpen: (isModalOpen: boolean) => ({ isModalOpen }),
        setEditMode: (editMode: 'create' | 'edit') => ({ editMode }),
        setDropdownVisible: (dropdownVisible: boolean) => ({ dropdownVisible }),
        setSelectedDataset: (dataset: DatasetReadApi | null) => ({ dataset }),
        setRecentDatasetIds: (recentDatasetIds: string[]) => ({ recentDatasetIds }),
        setRecentDatasets: (recentDatasets: DatasetReadApi[]) => ({ recentDatasets }),
        closeItemModal: (itemCreated: boolean = false) => ({ itemCreated }),
        datasetItemCreated: (datasetId: string) => ({ datasetId }),
        setModalItem: (modalItem: Partial<DatasetItemCreateApi> | null) => ({ modalItem }),
        retryStepRead: true,
    }),

    reducers(() => ({
        isModalOpen: [
            false as boolean,
            {
                setIsModalOpen: (_, { isModalOpen }) => isModalOpen,
            },
        ],

        selectedDataset: [
            null as DatasetReadApi | null,
            {
                setSelectedDataset: (_, { dataset }) => dataset,
            },
        ],

        modalItem: [
            null as Partial<DatasetItemCreateApi> | null,
            {
                setModalItem: (_, { modalItem }) => modalItem,
            },
        ],

        traceStepItemRequest: [
            null as TraceStepItemRequest | null,
            {
                loadTraceStepItem: (_, step) => ({ step, failure: null }),
                loadTraceStepItemFailure: (request, { errorObject }) =>
                    request && {
                        ...request,
                        failure: errorObject instanceof ApiError && errorObject.status === 404 ? 'not_found' : 'error',
                    },
            },
        ],

        editMode: [
            'create' as 'create' | 'edit',
            {
                setEditMode: (_, { editMode }) => editMode,
                setIsModalOpen: (state, { isModalOpen }) => (isModalOpen ? state : 'create'),
            },
        ],

        dropdownVisible: [
            false as boolean,
            {
                setDropdownVisible: (_, { dropdownVisible }) => dropdownVisible,
            },
        ],

        recentDatasetIds: [
            [] as string[],
            { persist: true },
            {
                setRecentDatasetIds: (_, { recentDatasetIds }) => truncateRecentDatasets(recentDatasetIds),
            },
        ],

        recentDatasets: [
            [] as DatasetReadApi[],
            {
                setRecentDatasets: (_, { recentDatasets }) => truncateRecentDatasets(recentDatasets),
            },
        ],
    })),

    loaders(({ actions, values, cache }) => ({
        traceStepItem: [
            null as TraceStepItem | null,
            {
                loadTraceStepItem: async (step: TraceStep, breakpoint) => {
                    // Calling the breakpoint when the read settles drops a read that another step's read
                    // replaced, so neither its result nor its failure is recorded against the current step.
                    const draft = await readTraceStepItem(cache, step).finally(() => breakpoint())
                    return { step, draft }
                },
            },
        ],

        datasetStore: [
            {} as Record<string, DatasetReadApi[]>,
            {
                loadDatasets: async (debounce: boolean = false, breakpoint) => {
                    if (debounce) {
                        await breakpoint(300)
                    }

                    const params = {
                        limit: DATASETS_PER_PAGE,
                        offset: 0,
                        search: values.searchForm.search || undefined,
                    }
                    const storageKey = getStorageKey(values.searchForm.search)
                    const response = await datasetsApi.listDatasets(params)
                    breakpoint()
                    return {
                        ...values.datasetStore,
                        [storageKey]: response.results,
                    }
                },
            },
        ],

        recentDatasets: [
            [] as DatasetReadApi[],
            {
                loadRecentDatasets: async (debounce: boolean = false, breakpoint) => {
                    if (debounce) {
                        await breakpoint(300)
                    }

                    if (values.recentDatasetIds.length === 0) {
                        return []
                    }

                    const response = await datasetsApi.listDatasets({
                        id__in: values.recentDatasetIds,
                        limit: RECENT_DATASETS_LIMIT,
                        offset: 0,
                    })
                    breakpoint()
                    const datasetsById = new Map(response.results.map((dataset) => [dataset.id, dataset]))
                    const recentDatasets = values.recentDatasetIds.flatMap((id) => {
                        const dataset = datasetsById.get(id)
                        return dataset && !dataset.archived ? [dataset] : []
                    })

                    if (recentDatasets.length !== values.recentDatasetIds.length) {
                        actions.setRecentDatasetIds(recentDatasets.map((dataset) => dataset.id))
                    }

                    return recentDatasets
                },
            },
        ],
    })),

    forms(({ asyncActions, actions, values, props, cache }) => ({
        searchForm: {
            defaults: { search: '', datasetId: null } as SearchFormValues,

            submit: async ({ datasetId }) => {
                // Dataset is not selected. Submit from the search input.
                if (!datasetId) {
                    await asyncActions.loadDatasets(true)
                    return
                }

                const item = props.step ? await stepDraftToSave({ actions, values, cache }, props.step) : null
                if (!item) {
                    return
                }

                // Close the dropdown.
                actions.setDropdownVisible(false)
                actions.resetSearchForm()

                // Find the selected dataset. Practically, this should always be found.
                const dataset = values.datasets?.find((dataset) => dataset.id === datasetId)
                if (!dataset) {
                    return
                }

                if (values.editMode === 'edit') {
                    // Open the modal.
                    actions.setModalItem(item)
                    actions.setSelectedDataset(dataset)
                    actions.setIsModalOpen(true)
                    return
                }

                try {
                    await datasetsApi.createItem({
                        dataset: datasetId,
                        client_item_id: item?.client_item_id,
                        input: item?.input ?? {},
                        expected_output: item?.expected_output,
                        source_output: item?.source_output,
                        metadata: item?.metadata,
                        source_trace_id: item?.source_trace_id,
                        source_event_id: item?.source_event_id,
                        source_timestamp: item?.source_timestamp,
                    })
                    actions.datasetItemCreated(datasetId)
                    lemonToast.success('Dataset item has been created successfully', {
                        button: {
                            label: 'View',
                            action: () => {
                                router.actions.push(urls.aiObservabilityDataset(datasetId))
                            },
                        },
                    })
                } catch (error) {
                    const detail = error instanceof ApiError ? error.detail : null
                    lemonToast.error(detail || "Couldn't add item to dataset. Try again.")
                }
            },
        },
    })),

    selectors({
        datasets: [
            (s) => [s.datasetStore, s.searchForm],
            (datasetStore: Record<string, DatasetReadApi[]>, searchForm: SearchFormValues): DatasetReadApi[] | null => {
                const storageKey = getStorageKey(searchForm.search)
                return datasetStore[storageKey] ?? null
            },
        ],

        isLoadingDatasets: [
            (s) => [s.datasets, s.datasetStoreLoading, s.recentDatasetsLoading],
            (
                datasets: DatasetReadApi[] | null,
                datasetStoreLoading: boolean,
                recentDatasetsLoading: boolean
            ): boolean => {
                return !datasets && (datasetStoreLoading || recentDatasetsLoading)
            },
        ],

        stepDraft: [
            (s, p) => [s.traceStepItem, p.step],
            (traceStepItem: TraceStepItem | null, step: TraceStep | null): DatasetItemDraft | null =>
                step && traceStepItem && isSameTraceStep(traceStepItem.step, step) ? traceStepItem.draft : null,
        ],

        stepReadStatus: [
            (s, p) => [s.stepDraft, s.traceStepItemRequest, p.step],
            (
                stepDraft: DatasetItemDraft | null,
                request: TraceStepItemRequest | null,
                step: TraceStep | null
            ): StepReadStatus | null => {
                if (stepDraft) {
                    return 'ready'
                }
                if (!step || !request || !isSameTraceStep(request.step, step)) {
                    return null
                }
                return request.failure ?? 'loading'
            },
        ],

        isModalMounted: [
            (s) => [s.editMode],
            (editMode: 'create' | 'edit'): boolean => {
                return editMode === 'edit'
            },
        ],
    }),

    listeners(({ actions, asyncActions, values, props }) => ({
        setIsModalOpen: () => {
            actions.setSearchFormValue('search', '')
        },

        closeItemModal: ({ itemCreated }) => {
            actions.setIsModalOpen(false)
            if (itemCreated && values.selectedDataset) {
                actions.datasetItemCreated(values.selectedDataset.id)
            }
        },

        datasetItemCreated: ({ datasetId }) => {
            aiObservabilityDatasetLogic.findMounted({ datasetId })?.actions.refreshAfterDatasetItemMutation()
        },

        setSearchFormValue: ({ name, value }) => {
            if (compareFieldName(name, 'search')) {
                asyncActions.loadDatasets(true)
            }

            if (compareFieldName(name, 'datasetId') && !values.recentDatasetIds.includes(value)) {
                const dataset = values.datasets?.find((dataset) => dataset.id === value)
                if (dataset) {
                    actions.setRecentDatasetIds([value, ...values.recentDatasetIds])
                    actions.setRecentDatasets([dataset, ...values.recentDatasets])
                }
            }
        },

        setDropdownVisible: ({ dropdownVisible }) => {
            if (dropdownVisible) {
                asyncActions.loadDatasets(true)
                if (props.step && values.stepReadStatus === null) {
                    actions.loadTraceStepItem(props.step)
                }
            } else {
                actions.setSearchFormValue('search', '')
            }
        },

        retryStepRead: () => {
            if (props.step) {
                actions.loadTraceStepItem(props.step)
            }
        },
    })),

    afterMount(({ actions, values }) => {
        if (!values.datasets?.length) {
            actions.loadDatasets(false)
            actions.loadRecentDatasets(false)
        }
    }),
])

async function stepDraftToSave(
    { actions, values, cache }: Pick<saveToDatasetButtonLogicType, 'actions' | 'values' | 'cache'>,
    step: TraceStep
): Promise<DatasetItemDraft | null> {
    if (values.stepDraft) {
        return values.stepDraft
    }
    if (values.stepReadStatus === 'error' || values.stepReadStatus === 'not_found') {
        return null
    }
    if (values.stepReadStatus === null) {
        actions.loadTraceStepItem(step)
    }
    try {
        return await readTraceStepItem(cache, step)
    } catch {
        // loadTraceStepItem reports this failure, and the open dropdown shows it.
        return null
    }
}

// The dropdown starts the read when it opens, and a pick waits for it. Both callers share one
// request per step, so a pick made while the read is in flight does not send a second read.
function readTraceStepItem(cache: Record<string, any>, step: TraceStep): Promise<DatasetItemDraft> {
    const pending: PendingTraceStepRead | null = cache.pendingTraceStepRead ?? null
    if (pending && isSameTraceStep(pending.step, step)) {
        return pending.promise
    }
    const promise = datasetsApi.getTraceStepItem(step).finally(() => {
        if (cache.pendingTraceStepRead?.promise === promise) {
            cache.pendingTraceStepRead = null
        }
    })
    cache.pendingTraceStepRead = { step, promise }
    return promise
}

export function getStorageKey(search: string): string {
    return encodeParams({
        limit: DATASETS_PER_PAGE,
        offset: 0,
        search,
    })
}

/**
 * Truncates the recent datasets to the first 3.
 * @param state - The current state.
 * @returns The updated state.
 */
export function truncateRecentDatasets<T>(state: T[]): T[] {
    return state.slice(0, RECENT_DATASETS_LIMIT)
}

/**
 * A field name from kea-forms is either a string or an array of strings. This function compares the name to the field name.
 * @param nameValue - The name to compare.
 * @param fieldName - The field name to compare.
 * @returns boolean
 */
export function compareFieldName(nameValue: string | number | (string | number)[], fieldName: string): boolean {
    if (Array.isArray(nameValue)) {
        return nameValue[0] === fieldName
    }
    return nameValue === fieldName
}
