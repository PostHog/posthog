import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { chunk } from 'lib/utils/arrays'
import { withTimeout } from 'lib/utils/async'
import { teamLogic } from 'scenes/teamLogic'

import type { LLMSentimentResult } from '../../../frontend/src/queries/schema/schema-general'
import {
    fetchHasSentimentEvaluations,
    fetchStoredGenerationSentiments,
    type GenerationSentimentLookup,
} from './sentimentQueries'
import type { GenerationSentiment } from './sentimentResults'
import { runWithConcurrency } from './utils'

const BATCH_MAX_SIZE = 100
const MAX_CONCURRENT_BATCHES = 2
const BATCH_TIMER_DISPOSABLE_KEY = 'generationSentimentBatchTimer'
// A query that stalls without erroring used to leave the cell on a skeleton for the whole visit.
// The deadline aborts the request instead, which turns the cell into a retry control.
const REQUEST_DEADLINE_MS = 30000

interface SentimentEvaluationsProbe {
    teamId: number
    result: Promise<boolean>
}

// Each reset starts a new generation of lookups. A batch from an earlier one carries a snapshot
// taken before the refresh, so it must not write over what the current generation resolved.
function currentSentimentEpoch(cache: Record<string, any>): number {
    return (cache.sentimentEpoch as number | undefined) ?? 0
}

// One probe per project, reused by every batch. A probe that fails or stalls reports "yes", so a
// flaky list request costs a scan instead of blanking the column.
function probeSentimentEvaluations(cache: Record<string, any>, teamId: number): Promise<boolean> {
    const probe = cache.sentimentEvaluationsProbe as SentimentEvaluationsProbe | undefined

    if (probe?.teamId === teamId) {
        return probe.result
    }

    const nextProbe: SentimentEvaluationsProbe = {
        teamId,
        result: withTimeout((signal) => fetchHasSentimentEvaluations(teamId, signal), REQUEST_DEADLINE_MS).catch(
            () => true
        ),
    }
    cache.sentimentEvaluationsProbe = nextProbe
    return nextProbe.result
}

