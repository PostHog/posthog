export const offlineItemInspectorLogic: LogicWrapper<offlineItemInspectorLogicType> =
    kea<offlineItemInspectorLogicType>([
        props({} as OfflineItemInspectorLogicProps),
        key(({ teamId, experimentId, itemId }) => `${teamId}:${experimentId}:${itemId}`),
        path((key) => ['products', 'ai_observability', 'offlineItemInspectorLogic', key]),
        actions({
            refreshItem: true,
            nextResults: (cursor: string) => ({ cursor }),
            previousResults: true,
        }),
        loaders(({ props, values }) => ({
            item: [
                null as OfflineItemReadApi | null,
                {
                    loadOfflineItem: async (_: void, breakpoint) => {
                        try {
                            const item = await api.aiObservabilityOfflineExperimentsItemsRetrieve(
                                String(props.teamId),
                                props.experimentId,
                                props.itemId
                            )
                            breakpoint()
                            return item
                        } catch (error) {
                            breakpoint()
                            throw error
                        }
                    },
                },
            ],
            itemPayload: [
                null as OfflineItemPayloadReadApi | null,
                {
                    loadOfflineItemPayload: async (_: void, breakpoint) => {
                        try {
                            const payload = await api.aiObservabilityOfflineExperimentsItemsPayloadRetrieve(
                                String(props.teamId),
                                props.experimentId,
                                props.itemId
                            )
                            breakpoint()
                            return payload
                        } catch (error) {
                            breakpoint()
                            throw error
                        }
                    },
                },
            ],
            results: [
                null as OfflineResultPageApi | null,
                {
                    loadOfflineItemResults: async (_: void, breakpoint) => {
                        try {
                            const page = await api.aiObservabilityOfflineExperimentsItemsResultsList(
                                String(props.teamId),
                                props.experimentId,
                                props.itemId,
                                { limit: 20, cursor: values.resultCursor || undefined }
                            )
                            breakpoint()
                            return page
                        } catch (error) {
                            breakpoint()
                            throw error
                        }
                    },
                },
            ],
            selectedResult: [
                null as OfflineResultReadApi | null,
                {
                    loadOfflineSelectedResult: async (_: void, breakpoint) => {
                        if (!props.resultId) {
                            return null
                        }
                        const existing = values.results?.results.find((result) => result.id === props.resultId)
                        if (existing) {
                            return existing
                        }
                        if (!props.scorerVersionId) {
                            throw new Error('Open a result from its score column to inspect its details.')
                        }
                        try {
                            const page = await api.aiObservabilityOfflineExperimentsItemsResultsList(
                                String(props.teamId),
                                props.experimentId,
                                props.itemId,
                                { scorer_version_ids: props.scorerVersionId, limit: 1 }
                            )
                            breakpoint()
                            const result = page.results.find((result) => result.id === props.resultId)
                            if (!result) {
                                throw new Error('This result is unavailable or you do not have access.')
                            }
                            return result
                        } catch (error) {
                            breakpoint()
                            throw error
                        }
                    },
                },
            ],
            resultPayload: [
                null as OfflineResultPayloadReadApi | null,
                {
                    loadOfflineResultPayload: async (_: void, breakpoint) => {
                        const selected = values.selectedResult
                        if (!selected) {
                            return null
                        }
                        try {
                            const payload = await api.aiObservabilityOfflineExperimentsResultsPayloadRetrieve(
                                String(props.teamId),
                                props.experimentId,
                                selected.id
                            )
                            breakpoint()
                            return payload
                        } catch (error) {
                            breakpoint()
                            throw error
                        }
                    },
                },
            ],
        })),
        reducers({
            resultCursors: [
                [] as string[],
                {
                    nextResults: (state, { cursor }) => [...state, cursor],
                    previousResults: (state) => state.slice(0, -1),
                    refreshItem: () => [],
                },
            ],
            itemError: [
                null as string | null,
                {
                    loadOfflineItem: () => null,
                    loadOfflineItemFailure: (_, { errorObject }) =>
                        offlineReadError(errorObject, 'Could not load this item. Try again.'),
                },
            ],
            itemPayloadError: [
                null as string | null,
                {
                    loadOfflineItemPayload: () => null,
                    loadOfflineItemPayloadFailure: (_, { errorObject }) =>
                        offlineReadError(errorObject, 'Could not load this payload. Try again.'),
                },
            ],
            resultsError: [
                null as string | null,
                {
                    loadOfflineItemResults: () => null,
                    loadOfflineItemResultsFailure: (_, { errorObject }) =>
                        offlineReadError(errorObject, 'Could not load results. Try again.'),
                },
            ],
            selectedResultError: [
                null as string | null,
                {
                    loadOfflineSelectedResult: () => null,
                    loadOfflineSelectedResultFailure: (_, { errorObject, error }) =>
                        offlineReadError(errorObject, error || 'Could not load the selected result. Try again.'),
                },
            ],
            resultPayloadError: [
                null as string | null,
                {
                    loadOfflineSelectedResult: () => null,
                    loadOfflineResultPayload: () => null,
                    loadOfflineResultPayloadFailure: (_, { errorObject }) =>
                        offlineReadError(errorObject, 'Could not load result details. Try again.'),
                },
            ],
        }),
        selectors({
            resultCursor: [
                (s) => [s.resultCursors],
                (cursors: string[]): string | null => cursors[cursors.length - 1] || null,
            ],
        }),
        listeners(({ actions }) => ({
            refreshItem: () => {
                actions.loadOfflineItem()
                actions.loadOfflineItemPayload()
                actions.loadOfflineItemResults()
                actions.loadOfflineSelectedResult()
            },
            nextResults: () => actions.loadOfflineItemResults(),
            previousResults: () => actions.loadOfflineItemResults(),
            loadOfflineSelectedResultSuccess: () => actions.loadOfflineResultPayload(),
        })),
        propsChanged(({ actions, props }, oldProps) => {
            if (props.resultId !== oldProps.resultId || props.scorerVersionId !== oldProps.scorerVersionId) {
                actions.loadOfflineSelectedResult()
            }
        }),
        afterMount(({ actions }) => actions.refreshItem()),
    ])
