export type offlineOverviewTrendLogicType = MakeLogicType<
    offlineOverviewTrendLogicValues,
    offlineOverviewTrendLogicActions,
    OfflineOverviewTrendLogicProps,
    offlineOverviewTrendLogicMeta
>

export const offlineOverviewTrendLogic: LogicWrapper<offlineOverviewTrendLogicType> =
    kea<offlineOverviewTrendLogicType>([
        props({} as OfflineOverviewTrendLogicProps),
        key(getOfflineOverviewTrendKey),
        path((key) => ['products', 'ai_observability', 'offlineOverviewTrendLogic', key]),
        actions({
            selectVersion: (versionId: string) => ({ versionId }),
        }),
        loaders(({ props }) => ({
            trend: [
                null as OfflineOverviewTrendResult | null,
                {
                    loadOfflineOverviewTrend: async (_ = null, breakpoint): Promise<OfflineOverviewTrendResult> => {
                        const query: OfflineOverviewTrendQuery = {
                            dateFrom: props.dateFrom,
                            dateTo: props.dateTo,
                            refreshKey: props.refreshKey,
                            filters: props.filters,
                        }
                        await breakpoint(150)
                        return withOfflineTrendReadLimit(async () => {
                            try {
                                breakpoint()
                                const definition = await api.llmAnalyticsScoreDefinitionsRetrieve(
                                    String(props.teamId),
                                    props.scorerId
                                )
                                breakpoint()
                                let page = await api.aiObservabilityOfflineScorersHistoryList(
                                    String(props.teamId),
                                    props.scorerId,
                                    {
                                        ...props.filters,
                                        date_from: props.dateFrom,
                                        date_to: props.dateTo,
                                        statuses: props.filters?.statuses || OFFLINE_ALL_UPLOAD_STATES,
                                        limit: 100,
                                    }
                                )
                                breakpoint()
                                const results = [...page.results]
                                for (
                                    let pagesLoaded = 1;
                                    page.next_cursor && pagesLoaded < MAX_HISTORY_PAGES;
                                    pagesLoaded++
                                ) {
                                    page = await api.aiObservabilityOfflineScorersHistoryList(
                                        String(props.teamId),
                                        props.scorerId,
                                        {
                                            ...props.filters,
                                            date_from: props.dateFrom,
                                            date_to: props.dateTo,
                                            statuses: props.filters?.statuses || OFFLINE_ALL_UPLOAD_STATES,
                                            limit: 100,
                                            cursor: page.next_cursor,
                                        }
                                    )
                                    breakpoint()
                                    results.push(...page.results)
                                }
                                return { definition, page: { ...page, results }, query }
                            } catch (error) {
                                breakpoint()
                                throw error
                            }
                        })
                    },
                },
            ],
        })),
        reducers({
            selectedVersionId: [null as string | null, { selectVersion: (_, { versionId }) => versionId }],
            trendError: [false, { loadOfflineOverviewTrend: () => false, loadOfflineOverviewTrendFailure: () => true }],
        }),
        selectors({
            points: [
                (s) => [s.trend],
                (trend: OfflineOverviewTrendResult | null): OfflineHistoryPointApi[] => trend?.page.results || [],
            ],
            versionSummaries: [
                (s) => [s.points],
                (points: OfflineHistoryPointApi[]): OfflineScoreHistorySummary[] => {
                    const byVersion = new Map<string, OfflineHistoryPointApi[]>()
                    for (const point of points) {
                        const versionPoints = byVersion.get(point.summary.scorer.id) || []
                        versionPoints.push(point)
                        byVersion.set(point.summary.scorer.id, versionPoints)
                    }
                    return [...byVersion.values()]
                        .map(aggregateOfflineScoreHistory)
                        .filter((summary): summary is OfflineScoreHistorySummary => summary !== null)
                        .sort((a, b) => b.scorer.version - a.scorer.version)
                },
            ],
            periodSummary: [
                (s) => [s.versionSummaries, s.selectedVersionId],
                (
                    summaries: OfflineScoreHistorySummary[],
                    selectedVersionId: string | null
                ): OfflineScoreHistorySummary | null =>
                    summaries.find((summary) => summary.scorer.id === selectedVersionId) || summaries[0] || null,
            ],
        }),
        afterMount(({ actions }) => actions.loadOfflineOverviewTrend()),
        propsChanged(({ actions, props }, previous) => {
            if (
                props.dateFrom !== previous.dateFrom ||
                props.dateTo !== previous.dateTo ||
                props.refreshKey !== previous.refreshKey ||
                !objectsEqual(props.filters || {}, previous.filters || {})
            ) {
                actions.loadOfflineOverviewTrend()
            }
        }),
    ])
