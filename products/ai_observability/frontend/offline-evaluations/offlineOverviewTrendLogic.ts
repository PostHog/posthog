import { objectsEqual } from 'lib/utils/objects'

import * as api from '../generated/api'
import type { OfflineHistoryPageApi, OfflineHistoryPointApi, ScoreDefinitionApi } from '../generated/api.schemas'
import {
    OFFLINE_ALL_UPLOAD_STATES,
    withOfflineTrendReadLimit,
    type OfflineOverviewTrendFilters,
} from './offlineOverviewState'
import { aggregateOfflineScoreHistory, type OfflineScoreHistorySummary } from './offlineScoreTrends'

export interface OfflineOverviewTrendLogicProps {
    teamId: number
    scorerId: string
    overviewId?: string
    dateFrom?: string
    dateTo: string
    refreshKey: number
    filters?: OfflineOverviewTrendFilters
}

export type OfflineOverviewTrendQuery = Pick<
    OfflineOverviewTrendLogicProps,
    'dateFrom' | 'dateTo' | 'refreshKey' | 'filters'
>

export interface OfflineOverviewTrendResult {
    definition: ScoreDefinitionApi
    page: OfflineHistoryPageApi
    query: OfflineOverviewTrendQuery
}

export type OfflineOverviewTrendState = Pick<offlineOverviewTrendLogicValues, 'trend' | 'trendLoading' | 'trendError'>

const EMPTY_TREND_STATES: Record<string, OfflineOverviewTrendState> = {}
const MAX_HISTORY_PAGES = 5

export function getOfflineOverviewTrendKey({
    teamId,
    scorerId,
    overviewId,
}: Pick<OfflineOverviewTrendLogicProps, 'teamId' | 'scorerId' | 'overviewId'>): string {
    return `${overviewId ?? teamId}:${scorerId}`
}

export function selectOfflineOverviewTrendStates(state: {
    products?: { ai_observability?: { offlineOverviewTrendLogic?: Record<string, OfflineOverviewTrendState> } }
}): Record<string, OfflineOverviewTrendState> {
    return state.products?.ai_observability?.offlineOverviewTrendLogic ?? EMPTY_TREND_STATES
}

