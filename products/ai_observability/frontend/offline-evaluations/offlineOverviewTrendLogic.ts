import { MakeLogicType, actions, afterMount, kea, key, path, props, propsChanged, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { objectsEqual } from 'lib/utils/objects'

import * as api from '../generated/api'
import type {
    OfflineHistoryPageApi,
    OfflineHistoryPointApi,
    OfflineScorerVersionReadApi,
    ScoreDefinitionApi,
} from '../generated/api.schemas'
import {
    OFFLINE_ALL_UPLOAD_STATES,
    withOfflineTrendReadLimit,
    type OfflineOverviewTrendFilters,
} from './offlineOverviewState'

export interface OfflineOverviewTrendLogicProps {
    teamId: number
    scorerId: string
    dateFrom?: string
    dateTo: string
    refreshKey: number
    filters?: OfflineOverviewTrendFilters
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface offlineOverviewTrendLogicValues {
    activeVersion: OfflineScorerVersionReadApi | null
    selectedVersionId: string | null
    trend: {
        definition: ScoreDefinitionApi
        page: OfflineHistoryPageApi
    } | null
    trendError: boolean
    trendLoading: boolean
    versionPoints: OfflineHistoryPointApi[]
    versions: OfflineScorerVersionReadApi[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface offlineOverviewTrendLogicActions {
    loadOfflineOverviewTrend: (_?: any) => any
    loadOfflineOverviewTrendFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadOfflineOverviewTrendSuccess: (
        trend: {
            definition: ScoreDefinitionApi
            page: OfflineHistoryPageApi
        },
        payload?: any
    ) => {
        trend: {
            definition: ScoreDefinitionApi
            page: OfflineHistoryPageApi
        }
        payload?: any
    }
    selectVersion: (versionId: string) => {
        versionId: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface offlineOverviewTrendLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        versions: (
            trend: {
                definition: ScoreDefinitionApi
                page: OfflineHistoryPageApi
            } | null
        ) => OfflineScorerVersionReadApi[]
        activeVersion: (
            versions: OfflineScorerVersionReadApi[],
            selectedVersionId: string | null
        ) => OfflineScorerVersionReadApi | null
        versionPoints: (
            trend: {
                definition: ScoreDefinitionApi
                page: OfflineHistoryPageApi
            } | null,
            activeVersion: OfflineScorerVersionReadApi | null
        ) => OfflineHistoryPointApi[]
    }
}

export type offlineOverviewTrendLogicType = MakeLogicType<
    offlineOverviewTrendLogicValues,
    offlineOverviewTrendLogicActions,
    OfflineOverviewTrendLogicProps,
    offlineOverviewTrendLogicMeta
>

export const offlineOverviewTrendLogic = kea<offlineOverviewTrendLogicType>([
    props({} as OfflineOverviewTrendLogicProps),
    key(({ teamId, scorerId }) => `${teamId}:${scorerId}`),
    path((key) => ['products', 'ai_observability', 'offlineOverviewTrendLogic', key]),
    actions({
        selectVersion: (versionId: string) => ({ versionId }),
    }),
    loaders(({ props }) => ({
        trend: [
            null as { definition: ScoreDefinitionApi; page: OfflineHistoryPageApi } | null,
            {
                loadOfflineOverviewTrend: async (_ = null, breakpoint) => {
                    await breakpoint(150)
                    return withOfflineTrendReadLimit(async () => {
                        try {
                            breakpoint()
                            const definition = await api.llmAnalyticsScoreDefinitionsRetrieve(
                                String(props.teamId),
                                props.scorerId
                            )
                            breakpoint()
                            const page = await api.aiObservabilityOfflineScorersHistoryList(
                                String(props.teamId),
                                props.scorerId,
                                {
                                    ...props.filters,
                                    date_from: props.dateFrom,
                                    date_to: props.dateTo,
                                    statuses: props.filters?.statuses || OFFLINE_ALL_UPLOAD_STATES,
                                    limit: 100,
                                }
                            )
                            breakpoint()
                            return { definition, page }
                        } catch (error) {
                            breakpoint()
                            throw error
                        }
                    })
                },
            },
        ],
    })),
    reducers({
        trendError: [false, { loadOfflineOverviewTrend: () => false, loadOfflineOverviewTrendFailure: () => true }],
        selectedVersionId: [null as string | null, { selectVersion: (_, { versionId }) => versionId }],
    }),
    selectors({
        versions: [
            (s) => [s.trend],
            (
                trend: {
                    definition: ScoreDefinitionApi
                    page: OfflineHistoryPageApi
                } | null
            ): OfflineScorerVersionReadApi[] =>
                [
                    ...new Map(trend?.page.results.map(({ summary }) => [summary.scorer.id, summary.scorer])).values(),
                ].sort((a, b) => b.version - a.version),
        ],
        activeVersion: [
            (s) => [s.versions, s.selectedVersionId],
            (
                versions: OfflineScorerVersionReadApi[],
                selectedVersionId: string | null
            ): OfflineScorerVersionReadApi | null =>
                versions.find((version) => version.id === selectedVersionId) || versions[0] || null,
        ],
        versionPoints: [
            (s) => [s.trend, s.activeVersion],
            (
                trend: {
                    definition: ScoreDefinitionApi
                    page: OfflineHistoryPageApi
                } | null,
                version: OfflineScorerVersionReadApi | null
            ): OfflineHistoryPointApi[] =>
                trend?.page.results.filter(({ summary }) => summary.scorer.id === version?.id) || [],
        ],
    }),
    afterMount(({ actions }) => actions.loadOfflineOverviewTrend()),
    propsChanged(({ actions, props }, previous) => {
        if (
            props.dateFrom !== previous.dateFrom ||
            props.dateTo !== previous.dateTo ||
            props.refreshKey !== previous.refreshKey ||
            !objectsEqual(props.filters || {}, previous.filters || {})
        ) {
            actions.loadOfflineOverviewTrend()
        }
    }),
])
