import { MakeLogicType, afterMount, kea, key, path, props, type BreakPointFunction, type LogicWrapper } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiError } from 'lib/api-error'

import { aiObservabilityOfflineExperimentsRetrieve } from '../generated/api'
import type { OfflineScorerSummaryApi } from '../generated/api.schemas'
import { runWithConcurrency } from '../utils'
import { loadOfflineRequest } from './loadOfflineRequest'
import type { ComparisonRun } from './offlineComparison'
import { offlineReadError } from './offlineResultPresentation'
import { readOfflineSummaryPages } from './offlineSummaryPages'

export interface OfflineComparisonProps {
    teamId: number
    experimentIds: string[]
}

type RunRead = ComparisonRun | { name: string; error: string }
type ComparisonReads = Record<string, RunRead>

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface offlineComparisonLogicValues {
    results: ComparisonReads | null
    resultsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface offlineComparisonLogicActions {
    loadComparison: (_: void) => void
    loadComparisonFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadComparisonSuccess: (
        results: ComparisonReads,
        payload?: void
    ) => {
        results: ComparisonReads
        payload?: void
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface offlineComparisonLogicMeta {
    key: string
}

export type offlineComparisonLogicType = MakeLogicType<
    offlineComparisonLogicValues,
    offlineComparisonLogicActions,
    OfflineComparisonProps,
    offlineComparisonLogicMeta
>

async function loadComparisonRun(teamId: number, id: string, breakpoint: BreakPointFunction): Promise<RunRead> {
    let name = id
    try {
        const experiment = await loadOfflineRequest(
            () => aiObservabilityOfflineExperimentsRetrieve(String(teamId), id),
            breakpoint
        )
        name = experiment.name
        const summaries: OfflineScorerSummaryApi[] = []
        if (experiment.visible_scorer_version_count) {
            await readOfflineSummaryPages(teamId, id, breakpoint, (page) => {
                summaries.push(...page.results)
            })
        }
        return { experiment, summaries }
    } catch (error) {
        breakpoint()
        return {
            name,
            error:
                error instanceof ApiError && error.status === 503
                    ? 'The request timed out or the service is unavailable.'
                    : offlineReadError(error, 'Could not load this experiment.'),
        }
    }
}

export const offlineComparisonLogic: LogicWrapper<offlineComparisonLogicType> = kea<offlineComparisonLogicType>([
    path(['products', 'ai_observability', 'offlineComparisonLogic']),
    props({} as OfflineComparisonProps),
    key((props) => `${props.teamId}:${[...props.experimentIds].sort().join(',')}`),
    loaders(({ props, values }) => ({
        results: [
            null as ComparisonReads | null,
            {
                loadComparison: async (_: void, breakpoint): Promise<ComparisonReads> => {
                    const { teamId, experimentIds } = props
                    const results = { ...values.results }
                    const ids = experimentIds.filter((id) => !results[id] || 'error' in results[id])
                    await runWithConcurrency(ids, 4, async (id) => {
                        breakpoint()
                        results[id] = await loadComparisonRun(teamId, id, breakpoint)
                    })
                    return results
                },
            },
        ],
    })),
    afterMount(({ actions }) => actions.loadComparison()),
])
