export const offlineExperimentsLogic = kea<offlineExperimentsLogicType>([
    props({} as OfflineExperimentsLogicProps),
    key(({ teamId, userId }) => `${teamId}:${userId}`),
    path((key) => ['products', 'ai_observability', 'offlineExperimentsLogic', key]),
    actions({
        setFilters: (filters: Partial<OfflineExperimentFilters>) => ({ filters }),
        setHasExperiments: (hasExperiments: boolean) => ({ hasExperiments }),
        hydrateUrl: (search: Record<string, unknown>) => ({ search }),
        setScorerIds: (scorerIds: string[]) => ({ scorerIds }),
        suggestScorerIds: (scorerIds: string[]) => ({ scorerIds }),
        openChooser: true,
        closeChooser: true,
        setScorerSearch: (search: string) => ({ search }),
        setScorerOffset: (offset: number) => ({ offset }),
        setDraftScorerIds: (scorerIds: string[]) => ({ scorerIds }),
        saveScorers: true,
        nextPage: (cursor: string) => ({ cursor }),
        previousPage: true,
        refresh: true,
    }),
    loaders(({ props, values, actions }) => ({
        experiments: [
            null as OfflineExperimentPageApi | null,
            {
                loadOfflineExperiments: async (_ = null, breakpoint) => {
                    try {
                        await breakpoint(150)
                        const { date_from, date_to, ...filters } = values.filters
                        const range = values.dateRange
                        if (!range) {
                            throw new Error('Choose a valid experiment date range.')
                        }
                        const page = await api.aiObservabilityOfflineExperimentsList(String(props.teamId), {
                            ...filters,
                            date_from: range.dateFrom,
                            date_to: range.dateTo,
                            cursor: values.cursor || undefined,
                            limit: 50,
                        })
                        breakpoint()
                        if (page.count > 0) {
                            actions.setHasExperiments(true)
                        } else if (values.hasExperiments !== true) {
                            const presence = await api.aiObservabilityOfflineExperimentsList(String(props.teamId), {
                                limit: 1,
                            })
                            breakpoint()
                            actions.setHasExperiments(presence.count > 0)
                        }
                        return page
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
        scorerOptions: [
            null as PaginatedScoreDefinitionListApi | null,
            {
                loadOfflineScorerOptions: async (_ = null, breakpoint) => {
                    try {
                        await breakpoint(150)
                        const page = await api.llmAnalyticsScoreDefinitionsList(String(props.teamId), {
                            search: values.scorerSearch || undefined,
                            offset: values.scorerOffset,
                            limit: 50,
                            order_by: 'name',
                        })
                        breakpoint()
                        return page
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
        suggestedScorers: [
            null as string[] | null,
            {
                loadOfflineSuggestedScorers: async (_ = null, breakpoint) => {
                    try {
                        const page = await api.aiObservabilityOfflineExperimentsList(String(props.teamId), {
                            statuses: 'completed',
                            limit: 50,
                        })
                        breakpoint()
                        const latest = page.results.find((experiment) => (experiment.visible_result_count || 0) > 0)
                        if (latest) {
                            const summaries = await api.aiObservabilityOfflineExperimentsScorerSummariesList(
                                String(props.teamId),
                                latest.id,
                                { limit: 100 }
                            )
                            breakpoint()
                            const scorerIds = [
                                ...new Set(
                                    summaries.results
                                        .filter((summary) => !summary.scorer.archived)
                                        .map((summary) => summary.scorer.definition_id)
                                ),
                            ].slice(0, 3)
                            if (scorerIds.length) {
                                return scorerIds
                            }
                        }
                        const definitions = await api.llmAnalyticsScoreDefinitionsList(String(props.teamId), {
                            archived: false,
                            limit: 3,
                            order_by: 'name',
                        })
                        breakpoint()
                        return definitions.results.filter((definition) => !definition.archived).map(({ id }) => id)
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers(({ props }) => ({
        filters: [
            { date_from: '-30d' } as OfflineExperimentFilters,
            {
                setFilters: (state, { filters }) => cleanOfflineFilters({ ...state, ...filters }),
                hydrateUrl: (_, { search }) => ({ date_from: '-30d', ...offlineFiltersFromUrl(search) }),
            },
        ],
        hasExperiments: [null as boolean | null, { setHasExperiments: (_, { hasExperiments }) => hasExperiments }],
        scorerIds: [
            null as string[] | null,
            {
                setScorerIds: (_, { scorerIds }) => scorerIds,
                suggestScorerIds: (state, { scorerIds }) => (!state?.length ? scorerIds : state),
                hydrateUrl: (_, { search }) =>
                    typeof search.scores === 'string'
                        ? (parseOfflineScorerIds(search.scores ? search.scores.split(',') : []) ?? [])
                        : readOfflineScorerPreferences(props.userId, props.teamId),
            },
        ],
        draftScorerIds: [[] as string[], { setDraftScorerIds: (_, { scorerIds }) => scorerIds }],
        chooserOpen: [false, { openChooser: () => true, closeChooser: () => false }],
        scorerSearch: ['', { setScorerSearch: (_, { search }) => search }],
        scorerOffset: [0, { setScorerOffset: (_, { offset }) => offset, setScorerSearch: () => 0 }],
        cursorStack: [
            [] as string[],
            {
                nextPage: (state, { cursor }) => [...state, cursor],
                previousPage: (state) => state.slice(0, -1),
                setFilters: () => [],
                hydrateUrl: (_, { search }) => offlineCursorStackFromUrl(search),
                refresh: () => [],
            },
        ],
        resolvedNow: [
            dayjs().toISOString(),
            {
                setFilters: () => dayjs().toISOString(),
                hydrateUrl: (_, { search }) => offlineListClockFromUrl(search) ?? dayjs().toISOString(),
                refresh: () => dayjs().toISOString(),
            },
        ],
        refreshKey: [0, { refresh: (state) => state + 1 }],
        experimentsError: [
            null as string | null,
            {
                loadOfflineExperiments: () => null,
                loadOfflineExperimentsFailure: (_, { error }) =>
                    error === 'Choose a valid experiment date range.'
                        ? error
                        : 'Could not load experiments. Check your access and try again.',
            },
        ],
        scorersById: [
            {} as Record<string, ScoreDefinitionApi>,
            {
                loadOfflineScorerOptionsSuccess: (state, { scorerOptions }) => ({
                    ...state,
                    ...Object.fromEntries(scorerOptions.results.map((scorer) => [scorer.id, scorer])),
                }),
            },
        ],
        scorerOptionsError: [
            false,
            { loadOfflineScorerOptions: () => false, loadOfflineScorerOptionsFailure: () => true },
        ],
    })),
    selectors({
        cursor: [(s) => [s.cursorStack], (stack: string[]): string | null => stack.at(-1) ?? null],
        dateRange: [
            (s) => [s.filters, s.resolvedNow, (_, props) => props.timezone],
            (filters: OfflineExperimentFilters, now: string, timezone): OfflineDateRange | null => {
                try {
                    return resolveOfflineDateRange(filters.date_from || '-30d', filters.date_to || null, now, timezone)
                } catch {
                    return null
                }
            },
        ],
        trendFilters: [
            (s) => [s.filters],
            (filters: OfflineExperimentFilters): OfflineOverviewTrendFilters => ({
                run_source: filters.run_source,
                statuses: filters.statuses || OFFLINE_ALL_UPLOAD_STATES,
            }),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        setFilters: () => {
            actions.loadOfflineExperiments()
            if (!values.scorerIds?.length && values.dateRange && values.suggestedScorers === null) {
                actions.loadOfflineSuggestedScorers()
            }
        },
        hydrateUrl: () => {
            actions.loadOfflineExperiments()
            if (!values.scorerIds?.length && values.dateRange) {
                if (values.suggestedScorers) {
                    actions.suggestScorerIds(values.suggestedScorers)
                } else {
                    actions.loadOfflineSuggestedScorers()
                }
            }
        },
        loadOfflineSuggestedScorersSuccess: ({ suggestedScorers }) => actions.suggestScorerIds(suggestedScorers),
        loadOfflineSuggestedScorersFailure: () => actions.suggestScorerIds([]),
        nextPage: () => actions.loadOfflineExperiments(),
        previousPage: () => actions.loadOfflineExperiments(),
        refresh: () => {
            actions.loadOfflineExperiments()
            if (!values.scorerIds?.length && values.dateRange) {
                actions.loadOfflineSuggestedScorers()
            }
        },
        openChooser: () => {
            actions.setDraftScorerIds(values.scorerIds || [])
            actions.loadOfflineScorerOptions()
        },
        setScorerSearch: () => actions.loadOfflineScorerOptions(),
        setScorerOffset: () => actions.loadOfflineScorerOptions(),
        saveScorers: () => {
            actions.setScorerIds(values.draftScorerIds)
            actions.closeChooser()
        },
        setScorerIds: ({ scorerIds }) => {
            saveOfflineScorerPreferences(props.userId, props.teamId, scorerIds)
            if (!scorerIds.length && values.dateRange) {
                actions.loadOfflineSuggestedScorers()
            }
        },
    })),
    actionToUrl(({ values }) => {
        const location = (): [string, Record<string, unknown>, Record<string, unknown>, { replace: boolean }] => [
            urls.aiObservabilityOfflineEvaluations(),
            {
                ...values.filters,
                scores: values.scorerIds?.join(','),
                cursor_stack: values.cursorStack.length ? values.cursorStack : undefined,
                list_now: values.cursorStack.length ? values.resolvedNow : undefined,
            },
            {},
            { replace: true },
        ]
        return {
            setFilters: location,
            setScorerIds: location,
            suggestScorerIds: location,
            nextPage: location,
            previousPage: location,
            refresh: location,
        }
    }),
    urlToAction(({ actions }) => ({
        [urls.aiObservabilityOfflineEvaluations()]: (_, search, __, { method }) => {
            if (method !== 'REPLACE') {
                actions.hydrateUrl(search)
            }
        },
    })),
    afterMount(({ actions }) => actions.hydrateUrl(router.values.searchParams)),
])
