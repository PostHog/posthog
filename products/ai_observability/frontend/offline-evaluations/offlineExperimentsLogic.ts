export const offlineExperimentsLogic: LogicWrapper<offlineExperimentsLogicType> = kea<offlineExperimentsLogicType>([
    props({} as OfflineExperimentsLogicProps),
    key(({ teamId, userId }) => `${teamId}:${userId}`),
    path((key) => ['products', 'ai_observability', 'offlineExperimentsLogic', key]),
    actions({
        toggleScoreTrends: true,
        initializeScoreTrends: true,
        setHoveredTrend: (chartId: string, timestamp: number) => ({ chartId, timestamp }),
        clearHoveredTrend: (chartId: string) => ({ chartId }),
        setFilters: (filters: Partial<OfflineExperimentFilters>) => ({ filters }),
        setHasExperiments: (hasExperiments: boolean) => ({ hasExperiments }),
        hydrateUrl: (search: Record<string, unknown>) => ({ search }),
        setScorerIds: (scorerIds: string[]) => ({ scorerIds }),
        suggestScorerIds: (scorerIds: string[]) => ({ scorerIds }),
        openChooser: true,
        closeChooser: true,
        setScorerSearch: (search: string) => ({ search }),
        setScorerOffset: (offset: number) => ({ offset }),
        setDraftScorerIds: (scorerIds: string[]) => ({ scorerIds }),
        setScorerDefinitions: (scorers: ScoreDefinitionApi[]) => ({ scorers }),
        saveScorers: true,
        nextPage: (cursor: string) => ({ cursor }),
        previousPage: true,
        refresh: true,
    }),
    loaders(({ props, values, actions }) => ({
        experiments: [
            null as OfflineExperimentPageApi | null,
            {
                loadOfflineExperiments: async (_ = null, breakpoint) => {
                    try {
                        await breakpoint(150)
                        const { date_from, date_to, ...filters } = values.filters
                        const range = values.dateRange
                        if (!range) {
                            throw new Error('Choose a valid experiment date range.')
                        }
                        const page = await api.aiObservabilityOfflineExperimentsList(String(props.teamId), {
                            ...filters,
                            tags: filters.tags?.length ? JSON.stringify(filters.tags) : undefined,
                            date_from: range.dateFrom,
                            date_to: range.dateTo,
                            cursor: values.cursor || undefined,
                            limit: 50,
                        })
                        breakpoint()
                        if (page.count > 0) {
                            actions.setHasExperiments(true)
                        } else if (values.hasExperiments !== true) {
                            const presence = await api.aiObservabilityOfflineExperimentsList(String(props.teamId), {
                                limit: 1,
                            })
                            breakpoint()
                            actions.setHasExperiments(presence.count > 0)
                        }
                        return page
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
        scorerOptions: [
            null as PaginatedScoreDefinitionListApi | null,
            {
                loadOfflineScorerOptions: async (_ = null, breakpoint) => {
                    try {
                        await breakpoint(150)
                        const page = await api.llmAnalyticsScoreDefinitionsList(String(props.teamId), {
                            search: values.scorerSearch || undefined,
                            offset: values.scorerOffset,
                            limit: 50,
                            order_by: 'name',
                        })
                        breakpoint()
                        return page
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
        suggestedScorers: [
            null as string[] | null,
            {
                loadOfflineSuggestedScorers: async (_ = null, breakpoint) => {
                    try {
                        const page = await api.aiObservabilityOfflineExperimentsList(String(props.teamId), {
                            statuses: 'completed',
                            limit: 50,
                        })
                        breakpoint()
                        const latest = page.results.find((experiment) => (experiment.visible_result_count || 0) > 0)
                        if (latest) {
                            const summaries = await api.aiObservabilityOfflineExperimentsScorerSummariesList(
                                String(props.teamId),
                                latest.id,
                                { limit: 100 }
                            )
                            breakpoint()
                            const scorerIds = [
                                ...new Set(
                                    summaries.results
                                        .filter((summary) => !summary.scorer.archived)
                                        .map((summary) => summary.scorer.definition_id)
                                ),
                            ].slice(0, 3)
                            if (scorerIds.length) {
                                return scorerIds
                            }
                        }
                        const definitions = await api.llmAnalyticsScoreDefinitionsList(String(props.teamId), {
                            archived: false,
                            limit: 3,
                            order_by: 'name',
                        })
                        breakpoint()
                        return definitions.results.filter((definition) => !definition.archived).map(({ id }) => id)
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers(({ props }) => ({
        scoreTrendsExpanded: [true, { persist: true }, { toggleScoreTrends: (expanded) => !expanded }],
        scoreTrendsInitialized: [false, { initializeScoreTrends: () => true }],
        filters: [
            { date_from: '-30d' } as OfflineExperimentFilters,
            {
                setFilters: (state, { filters }) => cleanOfflineFilters({ ...state, ...filters }),
                hydrateUrl: (_, { search }) => ({
                    date_from: '-30d',
                    ...offlineFiltersFromUrl(search),
                    ...restoreTagFilters('experiments', search, props.teamId, props.userId),
                }),
            },
        ],
        hasExperiments: [null as boolean | null, { setHasExperiments: (_, { hasExperiments }) => hasExperiments }],
        scorerIds: [
            null as string[] | null,
            {
                setScorerIds: (_, { scorerIds }) => scorerIds,
                suggestScorerIds: (state, { scorerIds }) => (!state?.length ? scorerIds : state),
                hydrateUrl: (_, { search }) =>
                    typeof search.scores === 'string'
                        ? (parseOfflineScorerIds(search.scores ? search.scores.split(',') : []) ?? [])
                        : readOfflineScorerPreferences(props.userId, props.teamId),
            },
        ],
        hoveredTrend: [
            null as { chartId: string; timestamp: number } | null,
            {
                setHoveredTrend: (_, { chartId, timestamp }) => ({ chartId, timestamp }),
                clearHoveredTrend: (state, { chartId }) => (state?.chartId === chartId ? null : state),
                setFilters: () => null,
                setScorerIds: () => null,
                hydrateUrl: () => null,
                refresh: () => null,
            },
        ],
        draftScorerIds: [[] as string[], { setDraftScorerIds: (_, { scorerIds }) => scorerIds }],
        chooserOpen: [false, { openChooser: () => true, closeChooser: () => false }],
        scorerSearch: ['', { setScorerSearch: (_, { search }) => search }],
        scorerOffset: [0, { setScorerOffset: (_, { offset }) => offset, setScorerSearch: () => 0 }],
        cursorStack: [
            [] as string[],
            {
                nextPage: (state, { cursor }) => [...state, cursor],
                previousPage: (state) => state.slice(0, -1),
                setFilters: () => [],
                hydrateUrl: (_, { search }) => offlineCursorStackFromUrl(search),
                refresh: () => [],
            },
        ],
        resolvedNow: [
            dayjs().toISOString(),
            {
                // Score trends ignore search, so a search keeps their date window and does not reload them.
                setFilters: (state, { filters }) =>
                    Object.keys(filters).every((key) => key === 'search') ? state : dayjs().toISOString(),
                hydrateUrl: (_, { search }) => offlineListClockFromUrl(search) ?? dayjs().toISOString(),
                refresh: () => dayjs().toISOString(),
            },
        ],
        refreshKey: [0, { refresh: (state) => state + 1 }],
        experimentsError: [
            null as string | null,
            {
                loadOfflineExperiments: () => null,
                loadOfflineExperimentsFailure: (_, { error }) =>
                    error === 'Choose a valid experiment date range.'
                        ? error
                        : 'Could not load experiments. Check your access and try again.',
            },
        ],
        scorersById: [
            {} as Record<string, ScoreDefinitionApi>,
            {
                loadOfflineScorerOptionsSuccess: (state, { scorerOptions }) => ({
                    ...state,
                    ...Object.fromEntries(scorerOptions.results.map((scorer) => [scorer.id, scorer])),
                }),
                setScorerDefinitions: (state, { scorers }) => ({
                    ...state,
                    ...Object.fromEntries(scorers.map((scorer) => [scorer.id, scorer])),
                }),
            },
        ],
        scorerOptionsError: [
            false,
            { loadOfflineScorerOptions: () => false, loadOfflineScorerOptionsFailure: () => true },
        ],
        suggestedScorersError: [
            false,
            { loadOfflineSuggestedScorers: () => false, loadOfflineSuggestedScorersFailure: () => true },
        ],
    })),
    selectors({
        cursor: [(s) => [s.cursorStack], (stack: string[]): string | null => stack.at(-1) ?? null],
        dateRange: [
            (s) => [s.filters, s.resolvedNow, (_, props) => props.timezone],
            (filters: OfflineExperimentFilters, now: string, timezone): OfflineDateRange | null => {
                try {
                    return resolveOfflineDateRange(filters.date_from || '-30d', filters.date_to || null, now, timezone)
                } catch {
                    return null
                }
            },
        ],
        trendFilters: [
            (s) => [s.filters],
            (filters: OfflineExperimentFilters): OfflineOverviewTrendFilters => ({
                run_source: filters.run_source,
                created_by: filters.created_by,
                created_by_is_null: filters.created_by_is_null,
                statuses: filters.statuses || OFFLINE_ALL_UPLOAD_STATES,
                tags: JSON.stringify(filters.tags || []),
                tag_match: filters.tag_match || 'any',
            }),
        ],
        trendXDomain: [
            (s) => [
                s.dateRange,
                s.scorerIds,
                selectOfflineOverviewTrendStates,
                s.trendFilters,
                s.refreshKey,
                (_, props: OfflineExperimentsLogicProps) => props,
            ],
            (
                dateRange: OfflineDateRange | null,
                scorerIds: string[] | null,
                trends: Record<string, OfflineOverviewTrendState>,
                filters: OfflineOverviewTrendFilters,
                refreshKey: number,
                props: OfflineExperimentsLogicProps
            ): [number, number] | undefined => {
                if (!dateRange) {
                    return undefined
                }
                const end = Date.parse(dateRange.dateTo)
                if (dateRange.dateFrom) {
                    return [Date.parse(dateRange.dateFrom), end]
                }
                const timestamps = (scorerIds || []).flatMap((scorerId) => {
                    const state =
                        trends[
                            getOfflineOverviewTrendKey({
                                teamId: props.teamId,
                                overviewId: `${props.teamId}:${props.userId}`,
                                scorerId,
                            })
                        ]
                    const trend = state?.trend
                    if (
                        !trend ||
                        state.trendLoading ||
                        state.trendError ||
                        trend.query.dateFrom !== dateRange.dateFrom ||
                        trend.query.dateTo !== dateRange.dateTo ||
                        trend.query.refreshKey !== refreshKey ||
                        trend.query.filters?.run_source !== filters.run_source ||
                        trend.query.filters?.created_by !== filters.created_by ||
                        trend.query.filters?.created_by_is_null !== filters.created_by_is_null ||
                        (trend.query.filters?.statuses || OFFLINE_ALL_UPLOAD_STATES) !== filters.statuses ||
                        (trend.query.filters?.tags || '[]') !== filters.tags ||
                        (trend.query.filters?.tag_match || 'any') !== filters.tag_match
                    ) {
                        return []
                    }
                    return trend.page.results
                        .map(({ experiment }) => Date.parse(experiment.started_at))
                        .filter(Number.isFinite)
                })
                const start = Math.min(...timestamps)
                return Number.isFinite(start) && start < end ? [start, end] : undefined
            },
        ],
    }),
    listeners(({ actions, values, props }) => ({
        toggleScoreTrends: () => {
            if (values.scoreTrendsExpanded && !values.scoreTrendsInitialized) {
                actions.initializeScoreTrends()
            }
        },
        initializeScoreTrends: () => {
            if (!values.scorerIds?.length && values.dateRange) {
                actions.loadOfflineSuggestedScorers()
            }
        },
        setFilters: () => {
            saveTagFilters('experiments', cleanTagFilters(values.filters), props.teamId, props.userId)
            actions.loadOfflineExperiments()
            if (
                values.scoreTrendsInitialized &&
                !values.scorerIds?.length &&
                values.dateRange &&
                values.suggestedScorers === null
            ) {
                actions.loadOfflineSuggestedScorers()
            }
        },
        hydrateUrl: () => {
            saveTagFilters('experiments', cleanTagFilters(values.filters), props.teamId, props.userId)
            actions.loadOfflineExperiments()
            if (values.scoreTrendsInitialized && !values.scorerIds?.length && values.dateRange) {
                if (values.suggestedScorers) {
                    actions.suggestScorerIds(values.suggestedScorers)
                } else {
                    actions.loadOfflineSuggestedScorers()
                }
            }
        },
        loadOfflineSuggestedScorersSuccess: ({ suggestedScorers }) => actions.suggestScorerIds(suggestedScorers),
        loadOfflineSuggestedScorersFailure: () => actions.suggestScorerIds([]),
        nextPage: () => actions.loadOfflineExperiments(),
        previousPage: () => actions.loadOfflineExperiments(),
        refresh: () => {
            actions.loadOfflineExperiments()
            if (values.scoreTrendsInitialized && !values.scorerIds?.length && values.dateRange) {
                actions.loadOfflineSuggestedScorers()
            }
        },
        openChooser: async (_, breakpoint) => {
            actions.setDraftScorerIds(values.scorerIds || [])
            actions.loadOfflineScorerOptions()
            // Selected scorers can sit outside the loaded options page or be archived, so fetch their names directly.
            const missing = (values.scorerIds || []).filter((id) => !values.scorersById[id])
            const scorers = await Promise.all(
                missing.map((id) =>
                    withOfflineTrendReadLimit(() =>
                        api.llmAnalyticsScoreDefinitionsRetrieve(String(props.teamId), id)
                    ).catch(() => null)
                )
            )
            breakpoint()
            actions.setScorerDefinitions(scorers.filter((scorer): scorer is ScoreDefinitionApi => scorer !== null))
        },
        setScorerSearch: () => actions.loadOfflineScorerOptions(),
        setScorerOffset: () => actions.loadOfflineScorerOptions(),
        saveScorers: () => {
            actions.setScorerIds(values.draftScorerIds)
            actions.closeChooser()
        },
        setScorerIds: ({ scorerIds }) => {
            saveOfflineScorerPreferences(props.userId, props.teamId, scorerIds)
            if (values.scoreTrendsInitialized && !scorerIds.length && values.dateRange) {
                actions.loadOfflineSuggestedScorers()
            }
        },
    })),
    actionToUrl(({ values }) => {
        const location = ():
            | [string, Record<string, unknown>, Record<string, unknown>, { replace: boolean }]
            | undefined => {
            if (
                removeProjectIdIfPresent(router.values.location.pathname) !==
                    urls.aiObservabilityOfflineEvaluations() ||
                router.values.searchParams.tab === 'datasets'
            ) {
                return
            }
            return [
                urls.aiObservabilityOfflineEvaluations(),
                {
                    tab: router.values.searchParams.tab === 'experiments' ? 'experiments' : undefined,
                    ...offlineFiltersToUrl(values.filters),
                    scores: values.scorerIds?.join(','),
                    cursor_stack: values.cursorStack.length ? values.cursorStack : undefined,
                    list_now: values.cursorStack.length ? values.resolvedNow : undefined,
                },
                {},
                { replace: true },
            ]
        }
        return {
            setFilters: location,
            hydrateUrl: location,
            setScorerIds: location,
            suggestScorerIds: location,
            nextPage: location,
            previousPage: location,
            refresh: location,
        }
    }),
    urlToAction(({ actions }) => ({
        [urls.aiObservabilityOfflineEvaluations()]: (_, search, __, { method }) => {
            if (method !== 'REPLACE' && search.tab !== 'datasets') {
                actions.hydrateUrl(search)
            }
        },
    })),
    afterMount(({ actions, values }) => {
        actions.hydrateUrl(router.values.searchParams)
        if (values.scoreTrendsExpanded) {
            actions.initializeScoreTrends()
        }
    }),
])
