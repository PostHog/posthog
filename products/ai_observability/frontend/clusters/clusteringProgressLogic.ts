import { MakeLogicType, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { llmAnalyticsClusteringConfigProgressList, llmAnalyticsClusteringConfigRetryCreate } from '../generated/api'
import type { ClusteringJobProgressApi } from '../generated/api.schemas'
import { clusteringConfigLogic } from './clusteringConfigLogic'
import type { ClusteringConfig } from './clusteringConfigLogic'
import { clusteringJobsLogic } from './clusteringJobsLogic'
import { clustersLogic } from './clustersLogic'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface clusteringProgressLogicValues {
    config: ClusteringConfig // clusteringConfigLogic
    currentTeamIdStrict: number | string // teamLogic
    progress: ClusteringJobProgressApi[]
    progressError: boolean
    progressLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface clusteringProgressLogicActions {
    loadProgress: () => any
    loadProgressFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadProgressSuccess: (
        progress: ClusteringJobProgressApi[],
        payload?: any
    ) => {
        progress: ClusteringJobProgressApi[]
        payload?: any
    }
    retryJob: (jobId: string) => string
    retryJobFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    retryJobSuccess: (
        progress: ClusteringJobProgressApi[],
        payload?: string
    ) => {
        progress: ClusteringJobProgressApi[]
        payload?: string
    }
}

export type clusteringProgressLogicType = MakeLogicType<clusteringProgressLogicValues, clusteringProgressLogicActions>

export const clusteringProgressLogic = kea<clusteringProgressLogicType>([
    path(['products', 'ai_observability', 'frontend', 'clusters', 'clusteringProgressLogic']),
    connect({ values: [teamLogic, ['currentTeamIdStrict'], clusteringConfigLogic, ['config']] }),
    loaders(({ values }) => ({
        progress: [
            [] as ClusteringJobProgressApi[],
            {
                loadProgress: async () =>
                    await llmAnalyticsClusteringConfigProgressList(String(values.currentTeamIdStrict)),
                retryJob: async (jobId: string) =>
                    await llmAnalyticsClusteringConfigRetryCreate(String(values.currentTeamIdStrict), {
                        job_id: jobId,
                    }),
            },
        ],
    })),
    reducers({
        progressError: [
            false,
            {
                loadProgressFailure: () => true,
                retryJobFailure: () => true,
                loadProgressSuccess: () => false,
                retryJobSuccess: () => false,
            },
        ],
    }),
    listeners(({ actions, cache }) => ({
        loadProgressSuccess: ({ progress }) => {
            const completed = progress
                .filter((job) => job.status === 'completed')
                .map((job) => `${job.job_id}:${job.updated_at}`)
                .join(',')
            if (
                cache.completed !== undefined &&
                completed &&
                completed !== cache.completed &&
                clustersLogic.isMounted()
            ) {
                clustersLogic.actions.loadClusteringRuns()
            }
            cache.completed = completed
        },
        [clusteringConfigLogic.actionTypes.saveEnabledSuccess]: () => actions.loadProgress(),
        [clusteringJobsLogic.actionTypes.loadJobsSuccess]: () => actions.loadProgress(),
    })),
    afterMount(({ actions, values, cache }) => {
        actions.loadProgress()
        cache.disposables.add(() => {
            const timer = window.setInterval(() => {
                if (
                    values.config.enabled &&
                    !values.progressLoading &&
                    (values.progressError ||
                        values.progress.some(
                            (job) => job.status && ['queued', 'waiting', 'preparing', 'clustering'].includes(job.status)
                        ))
                ) {
                    actions.loadProgress()
                }
            }, 10000)
            return () => window.clearInterval(timer)
        })
    }),
])
