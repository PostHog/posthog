import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { openAIConsentLegalDialog } from 'scenes/settings/organization/aiConsentCopy'
import { teamLogic } from 'scenes/teamLogic'

import { aiConsentLogic } from '~/layout/ai/aiConsentLogic'
import type { AnyPropertyFilter } from '~/types'

import {
    llmAnalyticsClusteringConfigList,
    llmAnalyticsClusteringConfigSetEnabledCreate,
    llmAnalyticsClusteringConfigSetEventFiltersCreate,
} from '../generated/api'
import type { ClusteringConfigApi } from '../generated/api.schemas'
import { clusteringJobsLogic } from './clusteringJobsLogic'

/** A filter is valid if it has a key set (not just an empty placeholder row). */
export function isValidFilter(f: AnyPropertyFilter): boolean {
    return 'key' in f && f.key !== undefined && f.key !== ''
}

export type ClusteringConfig = ClusteringConfigApi

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface clusteringConfigLogicValues {
    dataProcessingAccepted: boolean // aiConsentLogic
    dataProcessingApprovalDisabledReason: string | null // aiConsentLogic
    currentTeamIdStrict: number | string // teamLogic
    config: ClusteringConfig
    configLoading: boolean
    isSettingsPanelOpen: boolean
    localEventFilters: AnyPropertyFilter[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface clusteringConfigLogicActions {
    closeSettingsPanel: () => {
        value: true
    }
    loadConfig: () => any
    loadConfigFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadConfigSuccess: (
        config: ClusteringConfigApi,
        payload?: any
    ) => {
        config: ClusteringConfigApi
        payload?: any
    }
    openSettingsPanel: () => {
        value: true
    }
    saveEnabled: (enabled: boolean) => boolean
    saveEnabledFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    saveEnabledSuccess: (
        config: ClusteringConfigApi,
        payload?: boolean
    ) => {
        config: ClusteringConfigApi
        payload?: boolean
    }
    saveEventFilters: () => any
    saveEventFiltersFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    saveEventFiltersSuccess: (
        config: ClusteringConfigApi,
        payload?: any
    ) => {
        config: ClusteringConfigApi
        payload?: any
    }
    setEnabled: (enabled: boolean) => {
        enabled: boolean
    }
    setLocalEventFilters: (filters: AnyPropertyFilter[]) => {
        filters: AnyPropertyFilter[]
    }
}

export type clusteringConfigLogicType = MakeLogicType<clusteringConfigLogicValues, clusteringConfigLogicActions>

export const clusteringConfigLogic = kea<clusteringConfigLogicType>([
    path(['products', 'ai_observability', 'frontend', 'clusters', 'clusteringConfigLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamIdStrict'],
            aiConsentLogic,
            ['dataProcessingAccepted', 'dataProcessingApprovalDisabledReason'],
        ],
    })),

    actions({
        setEnabled: (enabled: boolean) => ({ enabled }),
        openSettingsPanel: true,
        closeSettingsPanel: true,
        setLocalEventFilters: (filters: AnyPropertyFilter[]) => ({ filters }),
    }),

    loaders(({ values }) => ({
        config: [
            { enabled: false, event_filters: [], created_at: '', updated_at: '' } as ClusteringConfig,
            {
                loadConfig: async () => {
                    return await llmAnalyticsClusteringConfigList(String(values.currentTeamIdStrict))
                },
                saveEnabled: async (enabled: boolean) =>
                    await llmAnalyticsClusteringConfigSetEnabledCreate(String(values.currentTeamIdStrict), { enabled }),
                saveEventFilters: async () => {
                    return await llmAnalyticsClusteringConfigSetEventFiltersCreate(String(values.currentTeamIdStrict), {
                        event_filters: values.localEventFilters.map((filter) => ({ ...filter })),
                    })
                },
            },
        ],
    })),

    reducers({
        isSettingsPanelOpen: [
            false,
            {
                openSettingsPanel: () => true,
                closeSettingsPanel: () => false,
                saveEventFiltersSuccess: () => false,
            },
        ],
        localEventFilters: [
            [] as AnyPropertyFilter[],
            {
                setLocalEventFilters: (_, { filters }) => filters,
                loadConfigSuccess: (_, { config }) => config.event_filters as AnyPropertyFilter[],
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        setEnabled: ({ enabled }) => {
            if (!enabled || values.dataProcessingAccepted) {
                actions.saveEnabled(enabled)
                return
            }
            openAIConsentLegalDialog({
                onConfirm: async () => {
                    await aiConsentLogic.asyncActions.acceptDataProcessing()
                    if (values.dataProcessingAccepted) {
                        actions.saveEnabled(true)
                    }
                },
            })
        },
        saveEnabledSuccess: ({ config }) => {
            lemonToast.success(config.enabled ? 'Clustering enabled' : 'Clustering disabled')
            if (clusteringJobsLogic.isMounted()) {
                clusteringJobsLogic.actions.loadJobs()
            }
        },
        saveEventFiltersSuccess: () => {
            lemonToast.success('Clustering filters saved')
        },
    })),

    afterMount(({ actions }) => {
        actions.loadConfig()
    }),
])
