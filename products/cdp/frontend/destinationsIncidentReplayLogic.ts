/** Whether the destination stores a credential of its own, which is what the incident could clear. */
function hasSecretInput(hogFunction: HogFunctionApi): boolean {
    return (hogFunction.inputs_schema ?? []).some((schema) => schema.secret)
}

/**
 * The incident start as a `scheduled_at` literal, in the team's timezone.
 *
 * Not `dateClauseFor`: that runs the bound through `dayjs.tz(value, zone)`, which reads the string
 * as wall time in the team's zone and discards the `Z`. The instant would shift by the team's
 * offset, so the count would cover a different span than the replay, which sends the same boundary
 * as UTC. Parsing as UTC first and rendering in the team's zone keeps the two in step.
 *
 * Exported for the unit test.
 */
export function incidentCountWindowStart(timezone: string): string {
    return dayjs(INCIDENT_WINDOW_START).tz(timezone).format('YYYY-MM-DD HH:mm:ss.SSS')
}

/**
 * Counts, per destination, the invocations whose latest status is still failed since the incident
 * began. One query rather than one per destination, and it doubles as the discovery step.
 *
 * There is deliberately no upper bound on `scheduled_at`: a replay writes its lifecycle rows into
 * the partition of the replay time, not the original one. Collapsing every partition from the
 * incident start onwards is what makes a recovered invocation read as succeeded, so a count shrinks
 * as a replay drains and the destination leaves the banner when it reaches zero. Leaving the bound
 * off also keeps the query text stable between mounts, which a `< now` bound did not.
 */
async function loadFailedCountsByDestination(): Promise<Map<string, number>> {
    const timezone = projectTimezoneOf(teamLogic.findMounted()?.values.currentTeam)
    const dateClause = hogql.raw(`AND scheduled_at >= '${incidentCountWindowStart(timezone)}'`)
    const query = hogql`
        SELECT function_id, count() AS failed_count FROM (
            SELECT
                function_id,
                invocation_id
            FROM posthog.hog_invocation_results
            WHERE function_kind = 'hog_function'
              ${dateClause}
            GROUP BY function_id, invocation_id
            HAVING argMax(is_deleted, version) = 0
               AND argMax(status, version) = 'failed'
        )
        GROUP BY function_id
        ORDER BY failed_count DESC
        LIMIT ${MAX_LISTED_DESTINATIONS}
    `
    const response = await api.queryHogQL(query, {
        scene: 'DestinationsIncidentReplay',
        productKey: 'pipeline_destinations',
    })

    const counts = new Map<string, number>()
    response.results?.forEach((row) => {
        if (Array.isArray(row) && row[0]) {
            counts.set(String(row[0]), Number(row[1] ?? 0))
        }
    })
    return counts
}

export const destinationsIncidentReplayLogic = kea<destinationsIncidentReplayLogicType>([
    path(['products', 'cdp', 'frontend', 'destinationsIncidentReplayLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        replayDestination: (id: string) => ({ id }),
        replayDestinationSuccess: (id: string) => ({ id }),
        replayDestinationFailure: (id: string) => ({ id }),
    }),
    loaders(({ values }) => ({
        affectedDestinations: [
            [] as AffectedDestination[],
            {
                loadAffectedDestinations: async () => {
                    if (!values.currentProjectId) {
                        return []
                    }
                    const projectId = String(values.currentProjectId)

                    // Two independent signals, because neither covers the whole recovery on its
                    // own. A destination still storing the mask is definitely broken, even with no
                    // traffic yet. One with failures but no mask has either had its credential
                    // entered again already, or broke for its own reasons - either way its failed
                    // invocations are still sitting there to replay.
                    //
                    // The masked-secrets lookup is the primary recovery signal and cheap, so its
                    // failure still fails the load. The failed-count query is heavy and its window
                    // grows daily, so a timeout on it must not hide the "Enter credentials" rows the
                    // masked-secrets signal builds on its own.
                    const [maskedSecrets, failedCounts] = await Promise.all([
                        hogFunctionsMaskedSecretsRetrieve(projectId),
                        loadFailedCountsByDestination().catch(() => new Map<string, number>()),
                    ])

                    const maskedIds = new Set(maskedSecrets.map((row) => String(row.id)))
                    const candidateIds = [...new Set([...maskedIds, ...failedCounts.keys()])]
                    if (candidateIds.length === 0) {
                        return []
                    }

                    // Fetch each destination by ID rather than intersecting with the list endpoint,
                    // which caps at a page size: in a project with more destinations than one page
                    // the affected ones can fall outside it and silently drop off the banner. Only a
                    // definitive 403 (no access) or 404 (hard-deleted, nothing to replay) drops a
                    // row. A transient failure keeps it, so a blip never hides the recovery path.
                    const dropped = new Set<string>()
                    const fetched = await Promise.all(
                        candidateIds.map(async (id) => {
                            try {
                                return await hogFunctionsRetrieve(projectId, id)
                            } catch (error) {
                                const status = (error as { status?: number }).status
                                if (status === 403 || status === 404) {
                                    dropped.add(id)
                                }
                                return null
                            }
                        })
                    )
                    const byId = new Map(
                        fetched
                            .filter((hogFunction): hogFunction is HogFunctionApi => hogFunction !== null)
                            .map((hogFunction) => [String(hogFunction.id), hogFunction])
                    )

                    return (
                        candidateIds
                            .filter((id) => !dropped.has(id))
                            // A destination with no secret input never held a credential we could clear,
                            // so a failure on it belongs to the destination, not to this incident. This
                            // drops every OAuth-backed destination (Slack, ads, Discord, Linear, GitHub),
                            // whose credentials live on the Integration record. A destination we could
                            // not fetch stays: an unknown schema must not hide a real recovery path.
                            .filter((id) => {
                                const hogFunction = byId.get(id)
                                return maskedIds.has(id) || !hogFunction || hasSecretInput(hogFunction)
                            })
                            .map((id) => {
                                const hogFunction = byId.get(id)
                                const maskedRow = maskedSecrets.find((row) => String(row.id) === id)
                                return {
                                    id,
                                    name: hogFunction?.name ?? maskedRow?.name ?? '',
                                    type: (hogFunction?.type ?? maskedRow?.type ?? null) as HogFunctionTypeType | null,
                                    failedCount: failedCounts.get(id) ?? 0,
                                    needsCredentials: maskedIds.has(id),
                                    enabled: hogFunction?.enabled ?? maskedRow?.enabled ?? false,
                                }
                            })
                            .sort((a, b) => b.failedCount - a.failedCount)
                    )
                },
            },
        ],
    })),
    reducers({
        replayStatusById: [
            {} as Record<string, ReplayStatus>,
            {
                replayDestination: (state, { id }) => ({ ...state, [id]: 'pending' }),
                replayDestinationSuccess: (state, { id }) => ({ ...state, [id]: 'queued' }),
                replayDestinationFailure: (state, { id }) => {
                    const { [id]: _discarded, ...rest } = state
                    return rest
                },
            },
        ],
    }),
    selectors({
        showBanner: [
            (s) => [s.featureFlags, s.affectedDestinations],
            (featureFlags: FeatureFlagsSet, affectedDestinations: AffectedDestination[]): boolean =>
                !!featureFlags[FEATURE_FLAGS.DESTINATIONS_INCIDENT_REPLAY] && affectedDestinations.length > 0,
        ],
    }),
    listeners(({ actions, values }) => ({
        replayDestination: async ({ id }) => {
            if (!values.currentProjectId) {
                actions.replayDestinationFailure(id)
                return
            }
            try {
                await hogFunctionsRerunCreate(String(values.currentProjectId), id, {
                    filter: incidentReplayWindow(new Date()),
                })
                actions.replayDestinationSuccess(id)
                lemonToast.success('Replay queued. Failed events will be sent again shortly.')
            } catch {
                actions.replayDestinationFailure(id)
                lemonToast.error("Couldn't queue the replay. Try again, and contact support if it keeps happening.")
            }
        },
    })),
    // A subscription instead of afterMount: flags can resolve after the logic mounts, and a
    // one-time mount check would then never load. This fires with the value at mount and again
    // when the flag flips on, so only flagged teams pay for the lookup query.
    subscriptions(({ actions }) => ({
        featureFlags: (featureFlags: FeatureFlagsSet, oldFeatureFlags: FeatureFlagsSet | undefined) => {
            const isOn = !!featureFlags[FEATURE_FLAGS.DESTINATIONS_INCIDENT_REPLAY]
            const wasOn = !!oldFeatureFlags?.[FEATURE_FLAGS.DESTINATIONS_INCIDENT_REPLAY]
            if (isOn && !wasOn) {
                actions.loadAffectedDestinations()
            }
        },
    })),
])
