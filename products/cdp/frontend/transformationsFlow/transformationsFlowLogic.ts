export const transformationsFlowLogic = kea<transformationsFlowLogicType>([
    path(['products', 'cdp', 'frontend', 'transformationsFlow', 'transformationsFlowLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], userLogic, ['user']],
    })),
    actions({
        selectStep: (id: string | null) => ({ id }),
        setMode: (mode: TransformationsFlowMode) => ({ mode }),
        setTestEventInput: (input: string) => ({ input }),
        runNextTestStep: true,
        runAllTestSteps: true,
        completeTestStep: (stepId: string, result: TestStepResult | null) => ({ stepId, result }),
        setTestRunning: (running: boolean) => ({ running }),
        resetTest: true,
    }),
    loaders(({ values }) => ({
        transformations: [
            null as HogFunctionType[] | null,
            {
                loadTransformations: async () => {
                    // `full` adds inputs and mappings, which the test step sends to the test API.
                    const response = await api.hogFunctions.list({ types: ['transformation'], limit: 300, full: true })
                    return response.results
                },
                moveTransformation: async ({ id, offset }: { id: string; offset: -1 | 1 }) => {
                    const orders = moveTransformation(values.orderedTransformations, id, offset)
                    if (!orders) {
                        return values.transformations
                    }
                    const reordered = await api.hogFunctions.rearrange(orders)
                    posthog.capture('transformations flow reordered', { offset })
                    return reordered
                },
                setTransformationEnabled: async ({
                    hogFunction,
                    enabled,
                }: {
                    hogFunction: HogFunctionType
                    enabled: boolean
                }) => {
                    const updated = await api.hogFunctions.update(hogFunction.id, { enabled })
                    return (values.transformations ?? []).map((item) => (item.id === updated.id ? updated : item))
                },
                syncTransformation: ({ hogFunction }: { hogFunction: HogFunctionType }) =>
                    (values.transformations ?? []).map((item) => (item.id === hogFunction.id ? hogFunction : item)),
            },
        ],
        eventFilterMode: [
            null as EventFilterMode | null,
            {
                loadEventFilterMode: async () => {
                    // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                    const data = await api.get(`api/projects/${values.currentTeamId}/event_filter/`)
                    return (data?.mode as EventFilterMode | undefined) ?? 'disabled'
                },
            },
        ],
    })),
    reducers({
        selectedStepId: [
            null as string | null,
            {
                selectStep: (_, { id }) => id,
            },
        ],
        mode: [
            'build' as TransformationsFlowMode,
            {
                setMode: (_, { mode }) => mode,
            },
        ],
        testEventInput: [
            defaultTestEventInput(),
            {
                setTestEventInput: (_, { input }) => input,
            },
        ],
        testResults: [
            {} as Record<string, TestStepResult>,
            {
                completeTestStep: (state, { stepId, result }) => (result ? { ...state, [stepId]: result } : state),
                resetTest: () => ({}),
            },
        ],
        testProgress: [
            0,
            {
                completeTestStep: (state) => state + 1,
                resetTest: () => 0,
            },
        ],
        testRunning: [
            false,
            {
                setTestRunning: (_, { running }) => running,
                resetTest: () => false,
            },
        ],
    }),
    selectors({
        visibleTransformations: [
            (s) => [s.transformations, s.user],
            (transformations: HogFunctionType[] | null, user: UserType | null): HogFunctionType[] =>
                (transformations ?? []).filter((hogFunction) => shouldShowHogFunction(hogFunction, user)),
        ],
        orderedTransformations: [
            (s) => [s.visibleTransformations],
            (visibleTransformations: HogFunctionType[]): HogFunctionType[] =>
                sortByExecutionOrder(visibleTransformations.filter((hogFunction) => hogFunction.enabled)),
        ],
        disabledTransformations: [
            (s) => [s.visibleTransformations],
            (visibleTransformations: HogFunctionType[]): HogFunctionType[] =>
                visibleTransformations.filter((hogFunction) => !hogFunction.enabled),
        ],
        steps: [
            (s) => [s.orderedTransformations],
            (orderedTransformations: HogFunctionType[]): FlowStep[] => buildFlowSteps(orderedTransformations),
        ],
        graph: [(s) => [s.steps], (steps: FlowStep[]) => buildFlowGraph(steps)],
        selectedStep: [
            (s) => [s.steps, s.selectedStepId],
            (steps: FlowStep[], selectedStepId: string | null): FlowStep | null =>
                steps.find((step) => step.id === selectedStepId) ?? null,
        ],
        // The "add" step is only a place in the canvas. The test event does not pass through it.
        testSteps: [(s) => [s.steps], (steps: FlowStep[]): FlowStep[] => steps.filter((step) => step.kind !== 'add')],
        testEvent: [
            (s) => [s.testEventInput],
            (testEventInput: string): TestEvent | null => {
                const parsed = tryJsonParse(testEventInput)
                return parsed && typeof parsed === 'object' && typeof parsed.event === 'string'
                    ? toTestEvent(parsed)
                    : null
            },
        ],
        testDroppedBy: [
            (s) => [s.testSteps, s.testResults],
            (testSteps: FlowStep[], testResults: Record<string, TestStepResult>): FlowStep | null =>
                testSteps.find((step) => testResults[step.id]?.outcome === 'dropped') ?? null,
        ],
        currentTestEvent: [
            (s) => [s.testEvent, s.testSteps, s.testResults, s.testProgress],
            (
                testEvent: TestEvent | null,
                testSteps: FlowStep[],
                testResults: Record<string, TestStepResult>,
                testProgress: number
            ): TestEvent | null => {
                let event = testEvent
                for (const step of testSteps.slice(0, testProgress)) {
                    const result = testResults[step.id]
                    if (result) {
                        event = result.output
                    }
                }
                return event
            },
        ],
        testFinished: [
            (s) => [s.testSteps, s.testProgress, s.testDroppedBy],
            (testSteps: FlowStep[], testProgress: number, testDroppedBy: FlowStep | null): boolean =>
                !!testDroppedBy || testProgress >= testSteps.length,
        ],
        nextTestStep: [
            (s) => [s.testSteps, s.testProgress, s.testFinished],
            (testSteps: FlowStep[], testProgress: number, testFinished: boolean): FlowStep | null =>
                testFinished ? null : (testSteps[testProgress] ?? null),
        ],
    }),
    listeners(({ actions, values }) => {
        const runTestStep = async (): Promise<boolean> => {
            const step = values.nextTestStep
            const input = values.currentTestEvent
            if (!step || !input) {
                return false
            }
            if (values.testProgress === 0) {
                posthog.capture('transformations flow test started', {
                    transformation_count: values.orderedTransformations.length,
                })
            }
            actions.selectStep(step.id)

            if (step.kind !== 'transformation' || !step.hogFunction) {
                actions.completeTestStep(step.id, null)
                return true
            }

            const configuration = sanitizeConfiguration(
                structuredClone(step.hogFunction) as HogFunctionConfigurationType
            ) as Record<string, any>
            configuration.template_id = step.hogFunction.template?.id

            try {
                const response = await api.hogFunctions.createTestInvocation(step.hogFunction.id, {
                    globals: { event: input },
                    configuration,
                    mock_async_functions: true,
                })
                const result = getTestStepResult(input, response)
                actions.completeTestStep(step.id, result)
                posthog.capture('transformations flow test step run', {
                    position: step.position,
                    outcome: result.outcome,
                })
                return result.outcome !== 'dropped'
            } catch {
                lemonToast.error(`Could not test "${step.hogFunction.name}". Check its configuration and try again.`)
                return false
            }
        }

        return {
            runNextTestStep: async () => {
                if (values.testRunning) {
                    return
                }
                actions.setTestRunning(true)
                try {
                    await runTestStep()
                } finally {
                    actions.setTestRunning(false)
                }
            },
            runAllTestSteps: async () => {
                if (values.testRunning) {
                    return
                }
                actions.setTestRunning(true)
                try {
                    let keepGoing = true
                    while (keepGoing && !values.testFinished) {
                        keepGoing = await runTestStep()
                    }
                } finally {
                    actions.setTestRunning(false)
                }
            },
            completeTestStep: () => {
                if (values.testFinished) {
                    posthog.capture('transformations flow test completed', {
                        dropped: !!values.testDroppedBy,
                    })
                }
            },
            setTestEventInput: () => {
                if (values.testProgress > 0) {
                    actions.resetTest()
                }
            },
            selectStep: ({ id }) => {
                const step = values.steps.find((item) => item.id === id)
                if (step && !values.testRunning) {
                    posthog.capture('transformations flow step selected', { kind: step.kind })
                }
            },
            setMode: ({ mode }) => {
                if (mode === 'build') {
                    actions.resetTest()
                }
            },
            // A changed order or a changed enabled state makes the test results out of date.
            moveTransformationSuccess: () => actions.resetTest(),
            setTransformationEnabledSuccess: () => actions.resetTest(),
            moveTransformationFailure: () => {
                lemonToast.error('Could not change the order. Refresh the page and try again.')
            },
            setTransformationEnabledFailure: () => {
                lemonToast.error('Could not update the transformation. Refresh the page and try again.')
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadTransformations()
        actions.loadEventFilterMode()
        posthog.capture('transformations flow view opened')
    }),
])
