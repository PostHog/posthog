import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { UniversalFiltersGroup } from '~/types'

import { tracingSpansImpactCreate } from 'products/tracing/frontend/generated/api'
import type { _TracingCountBodyApi, _TracingImpactResponseApi } from 'products/tracing/frontend/generated/api.schemas'

import { tracingDataLogic } from './tracingDataLogic'
import { type TracingFilters, tracingFiltersLogic } from './tracingFiltersLogic'

export interface TracingImpactLogicProps {
    id: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingImpactLogicValues {
    filters: TracingFilters // tracingFiltersLogic
    queryFilterGroup: UniversalFiltersGroup // tracingFiltersLogic
    utcDateRange: {
        date_from: string | null | undefined
        date_to: string | null | undefined
    } // tracingFiltersLogic
    currentTeamId: number | null // teamLogic
    impact: _TracingImpactResponseApi | null
    impactLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingImpactLogicActions {
    runQuery: () => void // tracingDataLogic
    loadImpact: (_: any) => any
    loadImpactFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadImpactSuccess: (
        impact: _TracingImpactResponseApi | null,
        payload?: any
    ) => {
        impact: _TracingImpactResponseApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingImpactLogicMeta {
    key: string
}

export type tracingImpactLogicType = MakeLogicType<
    tracingImpactLogicValues,
    tracingImpactLogicActions,
    TracingImpactLogicProps,
    tracingImpactLogicMeta
>

export const tracingImpactLogic = kea<tracingImpactLogicType>([
    props({} as TracingImpactLogicProps),
    key(({ id }) => id),
    path((key) => ['products', 'tracing', 'frontend', 'tracingImpactLogic', key]),
    connect(({ id }: TracingImpactLogicProps) => ({
        values: [
            tracingFiltersLogic({ id }),
            ['utcDateRange', 'queryFilterGroup', 'filters'],
            teamLogic,
            ['currentTeamId'],
        ],
        actions: [tracingDataLogic({ id }), ['runQuery']],
    })),
    loaders(({ cache, values }) => ({
        impact: [
            null as _TracingImpactResponseApi | null,
            {
                loadImpact: async (_, breakpoint) => {
                    await breakpoint(300)
                    // The serializer models `filterGroup` as a flat filter list, but the endpoint also
                    // accepts the nested group the viewer holds (the view normalizes both), so the
                    // request body needs a cast the generated type can't express.
                    const query = {
                        dateRange: values.utcDateRange,
                        serviceNames: values.filters.serviceNames.length > 0 ? values.filters.serviceNames : undefined,
                        filterGroup: values.queryFilterGroup,
                    } as unknown as _TracingCountBodyApi
                    // Re-adding the key aborts the superseded in-flight request, and unmount aborts
                    // the current one. A request is one-shot work, not background work, so a hidden
                    // tab must not abort it.
                    const controller = new AbortController()
                    cache.disposables.add(() => () => controller.abort(), 'impactRequest', {
                        pauseOnPageHidden: false,
                    })
                    let response: _TracingImpactResponseApi | null = null
                    try {
                        response = await tracingSpansImpactCreate(
                            String(values.currentTeamId),
                            { query },
                            { signal: controller.signal }
                        )
                    } catch {
                        // The strip is passive decoration: on failure show nothing rather than stale
                        // counts or the global error toast.
                    }
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers({
        impact: {
            // Clear on refresh so counts from the previous query never render next to the new
            // query's results.
            loadImpact: () => null,
        },
    }),
    listeners(({ actions }) => ({
        // runQuery is the viewer's execute-this-query entrypoint, so the strip refreshes with the
        // query — including a latency-heatmap brush, which lands as a date range plus duration
        // filters and re-queries through the same action. Bursts collapse in loadImpact's own
        // breakpoint.
        runQuery: () => actions.loadImpact(null),
    })),
    afterMount(({ actions }) => {
        // The data logic usually mounts (and fires its initial runQuery) before this logic exists,
        // so the first load has to be explicit.
        actions.loadImpact(null)
    }),
])
