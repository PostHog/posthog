import { MakeLogicType, connect, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { isUniversalGroupFilterLike } from 'lib/components/UniversalFilters/utils'
import { teamLogic } from 'scenes/teamLogic'

import type { UniversalFiltersGroup } from '~/types'

import { tracingSpansServiceHealthCreate } from 'products/tracing/frontend/generated/api'
import type { ServiceHealthResponseApi } from 'products/tracing/frontend/generated/api.schemas'

import { TRACING_SCENE_VIEWER_ID, tracingFiltersLogic } from './tracingFiltersLogic'
import type { TracingFilters } from './tracingFiltersLogic'

export interface TracingServicesLogicProps {
    id: string
}

// The endpoint's caps on returned rows and on the service filter.
const SERVICES_LIMIT = 200
const MAX_SERVICE_NAMES = 100

function hasPropertyFilters(group: UniversalFiltersGroup): boolean {
    return group.values.some((value) => (isUniversalGroupFilterLike(value) ? hasPropertyFilters(value) : true))
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingServicesLogicValues {
    currentTeamId: number | null // teamLogic
    filters: TracingFilters // tracingFiltersLogic
    queryFilterGroup: UniversalFiltersGroup // tracingFiltersLogic
    utcDateRange: {
        date_from: string | null | undefined
        date_to: string
    } // tracingFiltersLogic
    propertyFiltersIgnored: boolean
    serviceHealth: ServiceHealthResponseApi | null
    serviceHealthError: boolean
    serviceHealthLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingServicesLogicActions {
    loadServiceHealth: (_: any) => any
    loadServiceHealthFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadServiceHealthSuccess: (
        serviceHealth: ServiceHealthResponseApi | null,
        payload?: any
    ) => {
        serviceHealth: ServiceHealthResponseApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingServicesLogicMeta {
    key: string
}

export type tracingServicesLogicType = MakeLogicType<
    tracingServicesLogicValues,
    tracingServicesLogicActions,
    TracingServicesLogicProps,
    tracingServicesLogicMeta
>

export const tracingServicesLogic = kea<tracingServicesLogicType>([
    props({ id: TRACING_SCENE_VIEWER_ID } as TracingServicesLogicProps),
    key(({ id }) => id),
    path((key) => ['products', 'tracing', 'frontend', 'tracingServicesLogic', key]),
    connect(({ id }: TracingServicesLogicProps) => ({
        values: [
            tracingFiltersLogic({ id }),
            ['utcDateRange', 'filters', 'queryFilterGroup'],
            teamLogic,
            ['currentTeamId'],
        ],
    })),
    loaders(({ values, cache }) => ({
        serviceHealth: [
            null as ServiceHealthResponseApi | null,
            {
                loadServiceHealth: async (_, breakpoint) => {
                    const currentTeamId = values.currentTeamId
                    if (currentTeamId === null) {
                        return null
                    }
                    await breakpoint(100)
                    // Re-adding the key aborts the superseded request.
                    const controller = new AbortController()
                    cache.disposables.add(() => () => controller.abort(), 'serviceHealthRequest', {
                        pauseOnPageHidden: false,
                    })
                    const response = await tracingSpansServiceHealthCreate(
                        String(currentTeamId),
                        {
                            query: {
                                dateRange: values.utcDateRange,
                                serviceNames: values.filters.serviceNames.slice(0, MAX_SERVICE_NAMES),
                                compare: 'previous_period',
                                spanScope: 'entry',
                                orderBy: 'throughput',
                                limit: SERVICES_LIMIT,
                            },
                        },
                        { signal: controller.signal }
                    )
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers({
        serviceHealthError: [
            false,
            {
                loadServiceHealth: () => false,
                loadServiceHealthSuccess: () => false,
                loadServiceHealthFailure: () => true,
            },
        ],
    }),
    selectors({
        // The service health endpoint takes no property filters, so the table can't apply them.
        propertyFiltersIgnored: [
            (s) => [s.queryFilterGroup],
            (queryFilterGroup: UniversalFiltersGroup): boolean => hasPropertyFilters(queryFilterGroup),
        ],
    }),
])
