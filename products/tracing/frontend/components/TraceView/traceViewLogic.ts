export const traceViewLogic: LogicWrapper<traceViewLogicType> = kea<traceViewLogicType>([
    props({} as TraceViewLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'tracing', 'frontend', 'components', 'TraceView', 'traceViewLogic', key]),
    connect(() => ({
        values: [tracingCorrelationConfigLogic, ['sessionErrorBadgesEnabled'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        showTrace: (pinnedSpanId: string | null, tab: SpanInspectorTab | null) => ({ pinnedSpanId, tab }),
        setSpans: (spans: Span[]) => ({ spans }),
        selectSpan: (spanId: string | null) => ({ spanId }),
        selectNextSpan: true,
        selectPreviousSpan: true,
        collapseSelectedSpan: true,
        expandSelectedSpan: true,
        spanStepped: true,
        toggleSpanCollapsed: (spanId: string) => ({ spanId }),
        showAllChildren: (spanId: string) => ({ spanId }),
        toggleChain: (spanId: string) => ({ spanId }),
        keepSelectionOnScreen: true,
        setInspectorTab: (tab: SpanInspectorTab, surface?: TraceViewSurface) => ({ tab, surface: surface ?? null }),
        enableSpanKeys: (containerSelector: string) => ({ containerSelector }),
        disableSpanKeys: true,
        highlightOperation: (
            operationKey: string | null,
            surface?: TraceViewSurface,
            scope?: TraceOperationsScope
        ) => ({
            operationKey,
            surface: surface ?? null,
            scope: scope ?? null,
        }),
        revealSpans: (reveal: TraceDialogReveal) => ({ reveal }),
    }),
    reducers({
        spans: [
            [] as Span[],
            {
                showTrace: () => [],
                setSpans: (_, { spans }) => spans,
            },
        ],
        // The span the trace was opened on: it stays listed even inside a folded branch.
        pinnedSpanId: [
            null as string | null,
            {
                showTrace: (_, { pinnedSpanId }) => pinnedSpanId,
            },
        ],
        selectedSpanId: [
            null as string | null,
            {
                showTrace: (_, { pinnedSpanId }) => pinnedSpanId,
                selectSpan: (_, { spanId }) => spanId,
            },
        ],
        collapsedSpanIds: [
            new Set<string>(),
            {
                showTrace: () => new Set<string>(),
                toggleSpanCollapsed: (collapsed, { spanId }) => {
                    const next = new Set(collapsed)
                    if (!next.delete(spanId)) {
                        next.add(spanId)
                    }
                    return next
                },
                revealSpans: (collapsed, { reveal }) => {
                    const next = new Set(collapsed)
                    reveal.collapsedSpanIds.forEach((spanId) => next.delete(spanId))
                    return next
                },
            },
        ],
        fullChildListSpanIds: [
            new Set<string>(),
            {
                showTrace: () => new Set<string>(),
                showAllChildren: (shown, { spanId }) => new Set(shown).add(spanId),
                revealSpans: (shown, { reveal }) => new Set([...shown, ...reveal.fullChildListSpanIds]),
            },
        ],
        // Chains fold by default, so this holds the opened ones.
        openChainIds: [
            new Set<string>(),
            {
                showTrace: () => new Set<string>(),
                toggleChain: (opened, { spanId }) => {
                    const next = new Set(opened)
                    if (!next.delete(spanId)) {
                        next.add(spanId)
                    }
                    return next
                },
                revealSpans: (opened, { reveal }) => new Set([...opened, ...reveal.chainIds]),
            },
        ],
        // A tab the person picked sticks while they move between spans. Until they pick one, the
        // inspector chooses for the span in view.
        chosenInspectorTab: [
            null as SpanInspectorTab | null,
            {
                showTrace: (_, { tab }) => tab,
                setInspectorTab: (_, { tab }) => tab,
            },
        ],
        // The `compareRowKey` of the operation whose spans the tree highlights. The key only has a meaning
        // against the spans of one trace, so opening a trace clears it. The Operations tab is the only place
        // that explains the dimmed rows, so a switch to another tab clears it too. A switch to the Operations
        // tab itself keeps it, so that a caller can select the tab after the highlight.
        highlightedOperationKey: [
            null as string | null,
            {
                highlightOperation: (_, { operationKey }) => operationKey,
                showTrace: () => null,
                setInspectorTab: (key, { tab }) => (tab === 'operations' ? key : null),
            },
        ],
    }),
    selectors({
        spanTree: [
            (s) => [s.spans],
            (spans: Span[]): TraceViewTree => {
                const roots = buildSpanTree(spans)
                const nodesById = new Map<string, SpanNode>()
                const stack = [...roots]
                while (stack.length > 0) {
                    const node = stack.pop()!
                    nodesById.set(node.span.span_id, node)
                    stack.push(...node.children)
                }
                return { roots, nodesById, descendantCounts: countDescendantsById(roots) }
            },
        ],
        spanRows: [
            (s) => [s.spanTree, s.collapsedSpanIds, s.fullChildListSpanIds, s.openChainIds, s.pinnedSpanId],
            (
                spanTree: TraceViewTree,
                collapsedSpanIds: Set<string>,
                fullChildListSpanIds: Set<string>,
                openChainIds: Set<string>,
                pinnedSpanId: string | null
            ): TraceDialogRow[] =>
                buildTraceDialogRows(spanTree.roots, {
                    collapsedSpanIds,
                    fullChildListSpanIds,
                    openChainIds,
                    pinned: (pinnedSpanId && spanTree.nodesById.get(pinnedSpanId)) || null,
                }),
        ],
        flatSpans: [
            (s) => [s.spanRows],
            (spanRows: TraceDialogRow[]): SpanNode[] =>
                spanRows.flatMap((row) => {
                    const node = rowSpanNode(row)
                    return node ? [node] : []
                }),
        ],
        chainStartIds: [
            (s) => [s.spanRows],
            (spanRows: TraceDialogRow[]): { folded: Set<string>; opened: Set<string> } => {
                const folded = new Set<string>()
                const opened = new Set<string>()
                for (const row of spanRows) {
                    if (row.kind === 'chain') {
                        folded.add(row.nodes[0].span.span_id)
                    } else if (row.kind === 'span' && row.openChainLength) {
                        opened.add(row.node.span.span_id)
                    }
                }
                return { folded, opened }
            },
        ],
        selectedSpan: [
            (s) => [s.spans, s.selectedSpanId, s.summary],
            (spans: Span[], selectedSpanId: string | null, summary: TraceViewSummary): Span | null =>
                spans.find((span) => span.span_id === selectedSpanId) ?? summary.rootSpan ?? spans[0] ?? null,
        ],
        // The tree's "<parent span missing>" row selects an id that only appears as a parent id.
        missingParentSpanId: [
            (s) => [s.spanTree, s.selectedSpanId],
            (spanTree: TraceViewTree, selectedSpanId: string | null): string | null =>
                selectedSpanId && spanTree.nodesById.get(selectedSpanId)?.isMissingParent ? selectedSpanId : null,
        ],
        pinnedSpan: [
            (s) => [s.spans, s.pinnedSpanId],
            (spans: Span[], pinnedSpanId: string | null): Span | null =>
                pinnedSpanId ? (spans.find((span) => span.span_id === pinnedSpanId) ?? null) : null,
        ],
        activeInspectorTab: [
            (s) => [s.chosenInspectorTab, s.selectedSpan, s.sessionErrorBadgesEnabled],
            // An error span leads with its exceptions. Otherwise the logs lead.
            (chosen: SpanInspectorTab | null, selectedSpan: Span | null, errorsTabEnabled: boolean): SpanInspectorTab =>
                chosen ?? (errorsTabEnabled && selectedSpan?.status_code === 2 ? 'errors' : 'logs'),
        ],
        operationsTabEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TRACING_TRACE_OPERATIONS_TAB],
        ],
        // The spans of the highlighted operation and their ancestors, so that a row that hides a match stays bright.
        // With the flag off nothing dims, because no Operations tab is on screen to explain the dimmed rows.
        operationSubtreeMarks: [
            (s) => [s.spanTree, s.highlightedOperationKey, s.operationsTabEnabled],
            (
                spanTree: TraceViewTree,
                operationKey: string | null,
                operationsTabEnabled: boolean
            ): Set<SpanNode> | null =>
                operationsTabEnabled && operationKey ? markOperationSubtrees(spanTree.roots, operationKey) : null,
        ],
        // Worked out once per change of rows or key, not per rendered row, because a "more" row stands for
        // whole subtrees and J and K re-render the rows on screen.
        operationRowMatches: [
            (s) => [s.spanRows, s.highlightedOperationKey, s.operationSubtreeMarks, s.collapsedSpanIds],
            (
                spanRows: TraceDialogRow[],
                operationKey: string | null,
                subtreeMarks: Set<SpanNode> | null,
                collapsedSpanIds: Set<string>
            ): boolean[] | null =>
                operationKey && subtreeMarks
                    ? operationRowMatches(spanRows, operationKey, subtreeMarks, collapsedSpanIds)
                    : null,
        ],
        firstOperationRowIndex: [
            (s) => [s.operationRowMatches],
            (matches: boolean[] | null): number => matches?.indexOf(true) ?? -1,
        ],
        // AI event rows are synthetic and have no operation of their own.
        operationSpans: [(s) => [s.spans], (spans: Span[]): Span[] => spans.filter((span) => !isAiEventSpan(span))],
        serviceColorMap: [(s) => [s.spans], (spans: Span[]): Map<string, number> => buildServiceColorMap(spans)],
        timeline: [
            (s) => [s.spans],
            (spans: Span[]): TraceViewTimeline => {
                if (spans.length === 0) {
                    return { startUs: 0, durationUs: 0 }
                }
                const starts = spans.map((span) => parseTimestampUs(span.timestamp))
                const ends = spans.map((span, i) => starts[i] + span.duration_nano / 1_000)
                const startUs = Math.min(...starts)
                return { startUs, durationUs: Math.max(...ends) - startUs }
            },
        ],
        summary: [
            (s) => [s.spans],
            (spans: Span[]): TraceViewSummary => ({
                rootSpan: spans.find((span) => span.is_root_span) ?? null,
                spanCount: spans.length,
                serviceCount: new Set(spans.map((span) => span.service_name)).size,
                errorCount: spans.filter((span) => span.status_code === 2).length,
            }),
        ],
    }),
    listeners(({ values, actions, cache, selectors }) => ({
        enableSpanKeys: ({ containerSelector }) => {
            // Capture phase, and stopped there, so the page under the view does not also act on
            // the key: with log details open, the logs list binds J and K to its own cursor.
            cache.disposables.add(() => {
                const owner = Symbol('spanKeys')
                spanKeyOwners.push(owner)
                const onKeyDown = (event: KeyboardEvent): void => {
                    const target = event.target as HTMLElement | null
                    // A field behind the view can still hold focus, such as one that autofocused
                    // while the trace loaded. The person cannot see it, so the key is theirs to step with.
                    const typing =
                        !!target?.closest(containerSelector) &&
                        (['input', 'textarea', 'select'].includes(target.tagName.toLowerCase()) ||
                            target.isContentEditable)
                    // Only the most recently opened view steps, so a drawer opened over another
                    // does not move the selection underneath it too.
                    if (spanKeyOwners[spanKeyOwners.length - 1] !== owner) {
                        return
                    }
                    if (typing || event.isComposing || event.metaKey || event.ctrlKey || event.altKey) {
                        return
                    }
                    const step = {
                        j: actions.selectNextSpan,
                        k: actions.selectPreviousSpan,
                        arrowleft: actions.collapseSelectedSpan,
                        arrowright: actions.expandSelectedSpan,
                    }[event.key.toLowerCase()]
                    if (step) {
                        event.preventDefault()
                        event.stopPropagation()
                        step()
                    }
                }
                window.addEventListener('keydown', onKeyDown, { capture: true })
                return () => {
                    window.removeEventListener('keydown', onKeyDown, { capture: true })
                    const index = spanKeyOwners.indexOf(owner)
                    if (index >= 0) {
                        spanKeyOwners.splice(index, 1)
                    }
                }
            }, 'spanKeys')
        },
        disableSpanKeys: () => {
            cache.disposables.dispose('spanKeys')
        },
        // The inspector's tab bar passes a surface only for a click that changes the tab on screen, so a tab that
        // another logic sets, or a click on the tab already shown, sends nothing. The check against the previous
        // tab also stops a caller that passes a surface for the tab already active.
        setInspectorTab: ({ tab, surface }, _, __, previousState) => {
            if (surface && tab !== selectors.activeInspectorTab(previousState)) {
                // pinned: analytics event name, so renaming it breaks the insights built on it
                posthog.capture('tracing trace inspector tab changed', { tab, surface })
            }
        },
        highlightOperation: ({ operationKey, surface, scope }) => {
            if (!operationKey) {
                return
            }
            // pinned: analytics event name, so renaming it breaks the insights built on it
            posthog.capture('tracing trace operation highlighted', { surface, scope })
            // The first span of a large operation often sits past a child cap, in a folded chain, or under
            // a collapsed span. Open what hides it, so that the tree has a row to scroll to. The selection
            // stays where it is, because the inspector shows the Operations tab the person is using.
            const { roots, nodesById } = values.spanTree
            const target = firstOperationSpan(roots, operationKey)
            if (!target) {
                return
            }
            const reveal = revealSpanInRows(roots, target, {
                collapsedSpanIds: values.collapsedSpanIds,
                fullChildListSpanIds: values.fullChildListSpanIds,
                openChainIds: values.openChainIds,
                pinned: (values.pinnedSpanId && nodesById.get(values.pinnedSpanId)) || null,
            })
            // One action that only opens. The toggle actions flip state, and the trace dialog counts them as the
            // person's own collapse toggles.
            if (reveal.collapsedSpanIds.length + reveal.fullChildListSpanIds.length + reveal.chainIds.length > 0) {
                actions.revealSpans(reveal)
            }
        },
        // The missing-parent notice replaces the whole inspector, Operations tab included, so a highlight
        // left in place would dim rows with nothing on screen to explain it.
        selectSpan: () => {
            if (values.missingParentSpanId && values.highlightedOperationKey) {
                actions.highlightOperation(null)
            }
        },
        selectNextSpan: () => {
            actions.spanStepped()
            // A missing-parent row is selectable too, so step from it rather than from the root fallback.
            const currentId = values.missingParentSpanId ?? values.selectedSpan?.span_id
            const index = values.flatSpans.findIndex((node) => node.span.span_id === currentId)
            const next = values.flatSpans[Math.min(index + 1, values.flatSpans.length - 1)]
            if (next) {
                actions.selectSpan(next.span.span_id)
            }
        },
        selectPreviousSpan: () => {
            actions.spanStepped()
            const currentId = values.missingParentSpanId ?? values.selectedSpan?.span_id
            const index = values.flatSpans.findIndex((node) => node.span.span_id === currentId)
            const previous = values.flatSpans[Math.max(index - 1, 0)]
            if (previous) {
                actions.selectSpan(previous.span.span_id)
            }
        },
        // Left collapses the selected span, or moves up to its parent once there is nothing to collapse.
        collapseSelectedSpan: () => {
            const node = values.spanTree.nodesById.get(values.missingParentSpanId ?? values.selectedSpan?.span_id ?? '')
            if (!node) {
                return
            }
            actions.spanStepped()
            const spanId = node.span.span_id
            if (values.chainStartIds.opened.has(spanId)) {
                actions.toggleChain(spanId)
            } else if (node.children.length > 0 && !values.collapsedSpanIds.has(spanId)) {
                actions.toggleSpanCollapsed(spanId)
            } else if (node.parent) {
                // The parent can sit inside a folded chain, which stands for it on screen.
                const shown = new Set(values.flatSpans)
                let parent: SpanNode | null = node.parent
                while (parent && !shown.has(parent)) {
                    parent = parent.parent
                }
                if (parent) {
                    actions.selectSpan(parent.span.span_id)
                }
            }
        },
        // Right expands the selected span, or steps into its first child once it is open.
        expandSelectedSpan: () => {
            const node = values.spanTree.nodesById.get(values.missingParentSpanId ?? values.selectedSpan?.span_id ?? '')
            if (!node || node.children.length === 0) {
                return
            }
            if (values.chainStartIds.folded.has(node.span.span_id)) {
                actions.spanStepped()
                actions.toggleChain(node.span.span_id)
                return
            }
            if (!values.collapsedSpanIds.has(node.span.span_id)) {
                actions.selectNextSpan()
                return
            }
            actions.spanStepped()
            actions.toggleSpanCollapsed(node.span.span_id)
        },
        toggleSpanCollapsed: () => {
            actions.keepSelectionOnScreen()
        },
        toggleChain: () => {
            actions.keepSelectionOnScreen()
        },
        // The inspector must never show a span the list hides.
        keepSelectionOnScreen: () => {
            const selected = values.selectedSpanId ? values.spanTree.nodesById.get(values.selectedSpanId) : undefined
            if (!selected) {
                return
            }
            const shown = new Set(values.flatSpans)
            let node: SpanNode | null = selected
            while (node && !shown.has(node)) {
                node = node.parent
            }
            if (node && node !== selected) {
                actions.selectSpan(node.span.span_id)
            }
        },
    })),
])
