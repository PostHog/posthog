export type traceDialogLogicType = MakeLogicType<
    traceDialogLogicValues,
    traceDialogLogicActions,
    Record<string, any>,
    traceDialogLogicMeta
>

export const traceDialogLogic = kea<traceDialogLogicType>([
    path(['products', 'tracing', 'frontend', 'components', 'TraceDialog', 'traceDialogLogic']),
    connect(() => ({
        actions: [router, ['locationChanged']],
        values: [featureFlagLogic, ['featureFlags']],
    })),
    actions({
        openTraceDialog: (trace: TraceLinkParams) => ({ trace: { ...trace, spanId: inApiCase(trace.spanId) } }),
        closeTraceDialog: true,
        selectSpan: (spanId: string) => ({ spanId }),
    }),
    loaders(({ values }) => ({
        traceSpans: [
            null as TraceDialogSpans | null,
            {
                loadTraceSpans: async (trace: TraceLinkParams, breakpoint): Promise<TraceDialogSpans | null> => {
                    const dateRange = resolveTraceLookupRange(trace.ts)
                    const seen = new Set<string>()
                    const spans: Span[] = []
                    let offset: number | undefined = undefined
                    try {
                        for (let page = 0; page < TRACE_DIALOG_MAX_PAGES; page++) {
                            const response = await api.tracing.getTrace(trace.traceId, { dateRange, offset })
                            breakpoint()
                            // A page that adds no new span means the pages overlap, so paging further only repeats them.
                            const fresh = (response.results as Span[]).filter((span) => !seen.has(span.span_id))
                            fresh.forEach((span) => seen.add(span.span_id))
                            spans.push(...fresh)
                            if (!response.hasMore || response.nextOffset == null || fresh.length === 0) {
                                return { spans, truncated: false }
                            }
                            // Nobody is looking any more, so stop querying for further pages.
                            if (!values.isOpen) {
                                return { spans, truncated: true }
                            }
                            offset = response.nextOffset
                        }
                    } catch (error) {
                        // A failure from a load that a newer one replaced must not mark the newer trace as failed.
                        breakpoint()
                        throw error
                    }
                    return { spans, truncated: true }
                },
            },
        ],
    })),
    reducers({
        isOpen: [
            false,
            {
                openTraceDialog: () => true,
                closeTraceDialog: () => false,
            },
        ],
        // Survives close: useKeepMountedWhileOpen keeps the dialog rendered through its exit
        // animation, and clearing the trace then would flash an empty dialog.
        trace: [
            null as TraceLinkParams | null,
            {
                openTraceDialog: (_, { trace }) => trace,
            },
        ],
        traceSpans: {
            openTraceDialog: () => null,
        },
        traceSpansFailed: [
            false,
            {
                loadTraceSpans: () => false,
                loadTraceSpansFailure: () => true,
            },
        ],
        selectedSpanId: [
            null as string | null,
            {
                openTraceDialog: (_, { trace }) => trace.spanId ?? null,
                selectSpan: (_, { spanId }) => spanId,
            },
        ],
    }),
    selectors({
        // Every entry point checks this one place, so the flag cannot open the dialog from some
        // links and not others.
        dialogEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TRACING_TRACE_DIALOG],
        ],
        flatSpans: [
            (s) => [s.traceSpans],
            (traceSpans: TraceDialogSpans | null): SpanNode[] =>
                traceSpans ? flattenTree(buildSpanTree(traceSpans.spans), new Set()) : [],
        ],
        serviceColorMap: [
            (s) => [s.traceSpans],
            (traceSpans: TraceDialogSpans | null): Map<string, number> => buildServiceColorMap(traceSpans?.spans ?? []),
        ],
        timeline: [
            (s) => [s.traceSpans],
            (traceSpans: TraceDialogSpans | null): TraceDialogTimeline => {
                const spans = traceSpans?.spans ?? []
                if (spans.length === 0) {
                    return { startUs: 0, durationUs: 0 }
                }
                const starts = spans.map((span) => parseTimestampUs(span.timestamp))
                const ends = spans.map((span, i) => starts[i] + span.duration_nano / 1_000)
                const startUs = Math.min(...starts)
                return { startUs, durationUs: Math.max(...ends) - startUs }
            },
        ],
        summary: [
            (s) => [s.traceSpans],
            (traceSpans: TraceDialogSpans | null): TraceDialogSummary => {
                const spans = traceSpans?.spans ?? []
                return {
                    rootSpan: spans.find((span) => span.is_root_span) ?? null,
                    spanCount: spans.length,
                    serviceCount: new Set(spans.map((span) => span.service_name)).size,
                    errorCount: spans.filter((span) => span.status_code === 2).length,
                }
            },
        ],
        // When the record that opened the dialog was written: a log's timestamp, so its span can show
        // when the log fired. Parsed to microseconds, like the timeline, so sub-millisecond spans place it right.
        openedAtUs: [
            (s) => [s.trace],
            (trace: TraceLinkParams | null): number | null =>
                trace?.ts && dayjs(trace.ts).isValid() ? parseTimestampUs(trace.ts) : null,
        ],
    }),
    listeners(({ values, actions, cache }) => ({
        openTraceDialog: ({ trace }) => {
            actions.loadTraceSpans(trace)
        },
        locationChanged: ({ pathname }) => {
            // Query and hash changes fire locationChanged too, so only a new pathname closes the dialog.
            if (pathname === cache.lastPathname) {
                return
            }
            cache.lastPathname = pathname
            if (values.isOpen) {
                actions.closeTraceDialog()
            }
        },
    })),
    afterMount(({ cache }) => {
        cache.lastPathname = router.values.location.pathname
    }),
])
