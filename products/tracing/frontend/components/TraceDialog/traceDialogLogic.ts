export const traceDialogLogic = kea<traceDialogLogicType>([
    path(['products', 'tracing', 'frontend', 'components', 'TraceDialog', 'traceDialogLogic']),
    connect(() => ({
        actions: [
            traceDialogOpenLogic,
            ['openTraceDialog', 'closeTraceDialog'],
            traceViewLogic({ id: TRACE_DIALOG_VIEW_ID }),
            [
                'showTrace',
                'setSpans',
                'selectSpan',
                'setInspectorTab',
                'toggleSpanCollapsed',
                'toggleChain',
                'toggleRun',
                'spanStepped',
                'selectNextSpan',
                'selectPreviousSpan',
                'collapseSelectedSpan',
                'expandSelectedSpan',
                'enableSpanKeys',
                'disableSpanKeys',
            ],
        ],
        values: [
            traceDialogOpenLogic,
            ['isOpen', 'trace', 'openedFrom', 'entryPoint'],
            tracingCorrelationConfigLogic,
            [
                'configuredDistinctIdKeys',
                'configuredSessionIdKeys',
                'correlationLinksEnabled',
                'sessionErrorBadgesEnabled',
            ],
            tracingConfigLogic,
            ['traceViewMode'],
        ],
    })),
    actions({
        startSession: true,
        openInTracing: true,
        toggleInspector: true,
        toggleFullscreen: true,
    }),
    loaders(({ values }) => ({
        traceSpans: [
            null as TraceDialogSpans | null,
            {
                loadTraceSpans: async (trace: TraceLinkParams, breakpoint): Promise<TraceDialogSpans | null> => {
                    const dateRange = resolveTraceLookupRange(trace.ts)
                    const seen = new Set<string>()
                    const spans: Span[] = []
                    let offset: number | undefined = undefined
                    try {
                        for (let page = 0; page < TRACE_DIALOG_MAX_PAGES; page++) {
                            const response = await api.tracing.getTrace(trace.traceId, { dateRange, offset })
                            breakpoint()
                            // A page that adds no new span means the pages overlap, so paging further only repeats them.
                            const fresh = (response.results as Span[]).filter((span) => !seen.has(span.span_id))
                            fresh.forEach((span) => seen.add(span.span_id))
                            spans.push(...fresh)
                            if (!response.hasMore || response.nextOffset == null || fresh.length === 0) {
                                return { spans, truncated: false }
                            }
                            if (!values.isOpen) {
                                return { spans, truncated: true }
                            }
                            offset = response.nextOffset
                        }
                    } catch (error) {
                        // A failure from a load that a newer one replaced must not mark the newer trace as failed.
                        breakpoint()
                        throw error
                    }
                    return { spans, truncated: true }
                },
            },
        ],
    })),
    reducers({
        traceSpans: {
            openTraceDialog: () => null,
        },
        traceSpansFailed: [
            false,
            {
                loadTraceSpans: () => false,
                loadTraceSpansFailure: () => true,
            },
        ],
        inspectorOpen: [
            true,
            { persist: true },
            {
                toggleInspector: (open) => !open,
            },
        ],
        isFullscreen: [
            false,
            { persist: true },
            {
                toggleFullscreen: (fullscreen) => !fullscreen,
            },
        ],
    }),
    selectors({
        // A truncated trace may hold a second, conflicting person on a page the dialog never
        // loaded, so it names no one rather than risk naming the wrong one.
        traceIdentity: [
            (s) => [s.traceSpans, s.configuredDistinctIdKeys, s.configuredSessionIdKeys, s.correlationLinksEnabled],
            (
                traceSpans: TraceDialogSpans | null,
                distinctIdKeys: string[] | undefined,
                sessionIdKeys: string[] | undefined,
                linksEnabled: boolean
            ): TraceIdentity =>
                linksEnabled && traceSpans && !traceSpans.truncated
                    ? resolveTraceIdentity(traceSpans.spans, distinctIdKeys, sessionIdKeys)
                    : EMPTY_TRACE_IDENTITY,
        ],
        // The Errors tab's session scope follows the badge flag rather than the links flag, the
        // same split the drawer makes.
        traceSessionId: [
            (s) => [s.traceSpans, s.configuredSessionIdKeys, s.sessionErrorBadgesEnabled],
            (
                traceSpans: TraceDialogSpans | null,
                sessionIdKeys: string[] | undefined,
                badgesEnabled: boolean
            ): string | null =>
                badgesEnabled && traceSpans && !traceSpans.truncated
                    ? resolveTraceSessionId(traceSpans.spans, sessionIdKeys)
                    : null,
        ],
        // When the record that opened the dialog was written: a log's timestamp, so its span can show
        // when the log fired. Parsed to microseconds, like the timeline, so sub-millisecond spans place it right.
        openedAtUs: [
            (s) => [s.trace, s.openedFrom],
            (trace: TraceLinkParams | null, openedFrom: TraceDialogSource | null): number | null =>
                // Other links pass a time near the trace, not the moment anything happened in it.
                openedFrom && trace?.ts && dayjs(trace.ts).isValid() ? parseTimestampUs(trace.ts) : null,
        ],
    }),
    // pinned: analytics event names and properties. Renaming one breaks the dashboards built on it.
    listeners(({ values, actions, cache }) => ({
        openTraceDialog: () => {
            actions.startSession()
        },
        startSession: () => {
            const { trace, openedFrom, entryPoint } = values
            if (!trace || !entryPoint) {
                return
            }
            // Opening another trace over an open dialog ends the first session.
            if (cache.session) {
                captureClosed(cache.session, 'replaced')
            }
            const session: TraceDialogSession = {
                entryPoint,
                openedAtMs: Date.now(),
                loadStartedAtMs: Date.now(),
                spansSelected: 0,
                keyboardSteps: 0,
                collapseToggles: 0,
                tabsViewed: new Set(),
            }
            cache.session = session
            posthog.capture('tracing trace dialog opened', {
                entry_point: entryPoint,
                has_span: !!trace.spanId,
                has_log: !!openedFrom,
                // The view persists across traces, so the view change event alone cannot count the traces read
                // as a call tree.
                view: values.traceViewMode,
            })
            actions.showTrace(trace.spanId ?? null, null)
            actions.loadTraceSpans(trace)
            actions.enableSpanKeys(TRACE_DIALOG_SELECTOR, 'trace_dialog')
        },
        closeTraceDialog: ({ reason }) => {
            actions.disableSpanKeys()
            const session: TraceDialogSession | undefined = cache.session
            if (!session) {
                return
            }
            cache.session = undefined
            captureClosed(session, reason)
        },
        openInTracing: () => {
            // Close here rather than on navigation: from /tracing itself the link only changes the query.
            actions.closeTraceDialog('open_in_tracing')
        },
        loadTraceSpans: () => {
            if (cache.session) {
                cache.session.loadStartedAtMs = Date.now()
            }
        },
        loadTraceSpansSuccess: ({ traceSpans }) => {
            actions.setSpans(traceSpans?.spans ?? [])
            if (!cache.session || !traceSpans) {
                return
            }
            posthog.capture('tracing trace dialog loaded', {
                entry_point: cache.session.entryPoint,
                span_count: traceSpans.spans.length,
                truncated: traceSpans.truncated,
                load_ms: Date.now() - cache.session.loadStartedAtMs,
            })
        },
        loadTraceSpansFailure: () => {
            if (cache.session) {
                posthog.capture('tracing trace dialog load failed', { entry_point: cache.session.entryPoint })
            }
        },
        selectSpan: () => {
            if (cache.session) {
                cache.session.spansSelected += 1
            }
        },
        setInspectorTab: ({ tab }) => {
            cache.session?.tabsViewed.add(tab)
        },
        spanStepped: () => {
            if (cache.session) {
                cache.session.keyboardSteps += 1
            }
        },
        toggleSpanCollapsed: () => {
            if (cache.session) {
                cache.session.collapseToggles += 1
            }
        },
        toggleChain: () => {
            if (cache.session) {
                cache.session.collapseToggles += 1
            }
        },
        toggleRun: () => {
            if (cache.session) {
                cache.session.collapseToggles += 1
            }
        },
    })),
    afterMount(({ values, actions }) => {
        // The dialog mounts this logic after traceDialogOpenLogic opens it, so the open action has
        // already gone by and the session starts here.
        if (values.isOpen) {
            actions.startSession()
        }
    }),
])
