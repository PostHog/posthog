// The trace endpoint pages at 2,000 spans, so this caps the dialog at 10,000. Bigger traces open in
// Tracing, which pages in on scroll.
const TRACE_DIALOG_MAX_PAGES = 5

// Pinned: autocapture and the span keys both match on the dialog's data-attr.
export const TRACE_DIALOG_DATA_ATTR = 'trace-dialog'
const TRACE_DIALOG_SELECTOR = `[data-attr="${TRACE_DIALOG_DATA_ATTR}"]`

export const TRACE_DIALOG_VIEW_ID = 'trace-dialog'

// The trace API returns hex span ids in uppercase, and logs and metrics carry them in lowercase. The
// dialog matches the opened span against the loaded spans exactly, so it keeps the API's case.
function inApiCase(spanId: string | null | undefined): string | null {
    if (!spanId) {
        return null
    }
    return usableId(spanId) ? spanId.toUpperCase() : spanId
}

export interface TraceDialogSpans {
    spans: Span[]
    truncated: boolean
}

/** The log the dialog was opened from, shown above the tree so the reason for the trace stays in view. */
export interface TraceDialogSource {
    body: string
    severity: LogSeverityLevel
}

/** Where a trace dialog was opened from. Sent with every dialog event, so keep the values stable. */
export type TraceDialogEntryPoint =
    | 'log_details'
    | 'log_expanded_row'
    | 'log_row_action'
    | 'log_trace_id_cell'
    | 'metric_sample'
    | 'metric_exemplar'

export type TraceDialogCloseReason = 'dismissed' | 'back_to_log' | 'open_in_tracing' | 'navigated' | 'replaced'

export interface OpenTraceDialogOptions {
    entryPoint: TraceDialogEntryPoint
    openedFrom?: TraceDialogSource | null
}

interface TraceDialogSession {
    entryPoint: TraceDialogEntryPoint
    openedAtMs: number
    loadStartedAtMs: number
    spansSelected: number
    keyboardSteps: number
    collapseToggles: number
    tabsViewed: Set<SpanInspectorTab>
}

function captureClosed(session: TraceDialogSession, reason: TraceDialogCloseReason): void {
    posthog.capture('tracing trace dialog closed', {
        entry_point: session.entryPoint,
        reason,
        seconds_open: Math.round((Date.now() - session.openedAtMs) / 1000),
        spans_selected: session.spansSelected,
        keyboard_steps: session.keyboardSteps,
        collapse_toggles: session.collapseToggles,
        tabs_viewed: [...session.tabsViewed],
    })
}

