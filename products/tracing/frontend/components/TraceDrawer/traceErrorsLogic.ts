export type traceErrorsLogicType = MakeLogicType<
    traceErrorsLogicValues,
    traceErrorsLogicActions,
    TraceErrorsLogicProps,
    traceErrorsLogicMeta
>

function eventFilter(key: string, value: string): AnyPropertyFilter {
    return {
        type: PropertyFilterType.Event,
        key,
        value,
        operator: PropertyOperator.Exact,
    } as AnyPropertyFilter
}

// An SDK that propagated the trace context stamps the exception with `$trace_id` and `$span_id`,
// which names the span that threw. Without those the only join left is the session plus a time
// window, and those issues co-occurred with the trace rather than being caused by it.
//
// This runs the query node rather than the generated issues-list client, because that endpoint
// defaults to active issues and to excluding test accounts. The badge counts every exception it
// matched, so the tab has to answer over the same set or the two disagree.
export const traceErrorsLogic = kea<traceErrorsLogicType>([
    props({} as TraceErrorsLogicProps),
    // The session is in the key, not just the trace: a trace that touches two sessions answers a
    // different question for each, and walking to a span of the other session has to re-ask. The
    // timestamp is in it too, because the root span, which sets it, can arrive on a later page.
    key((props) => `${props.traceId}:${props.spanId ?? ''}:${props.sessionId ?? ''}:${props.timestamp ?? ''}`),
    path((key) => ['products', 'tracing', 'frontend', 'components', 'TraceDrawer', 'traceErrorsLogic', key]),

    actions({
        setScope: (scope: TraceErrorsScope) => ({ scope }),
    }),

    loaders(({ props, values }) => ({
        issues: {
            __default: [] as MaxErrorTrackingIssuePreview[],
            loadIssues: async (): Promise<MaxErrorTrackingIssuePreview[]> => {
                const scope = values.effectiveScope
                if (!scope) {
                    return []
                }
                // The exact scopes only have to cover the trace's own run. The session scope is the
                // wider guess, so it keeps the wider window.
                const range =
                    scope === 'session' ? sessionErrorsWindow([props.timestamp]) : traceErrorsWindow([props.timestamp])
                if (!range) {
                    return []
                }

                // Spans read their ids back as uppercase hex, while the SDKs write them lowercase.
                const traceId = usableId(props.traceId)
                const spanId = usableId(props.spanId)
                const filters: AnyPropertyFilter[] = []
                if (scope === 'session' && props.sessionId) {
                    filters.push(eventFilter('$session_id', props.sessionId))
                } else if (traceId) {
                    filters.push(eventFilter('$trace_id', traceId))
                    // A span id is only unique inside its trace, so both ids bound the span scope.
                    if (scope === 'span' && spanId) {
                        filters.push(eventFilter('$span_id', spanId))
                    }
                }
                if (filters.length === 0) {
                    return []
                }

                const query: ErrorTrackingQuery = {
                    kind: NodeKind.ErrorTrackingQuery,
                    orderBy: 'last_seen',
                    dateRange: range,
                    filterGroup: {
                        type: FilterLogicalOperator.And,
                        values: [
                            {
                                type: FilterLogicalOperator.And,
                                values: filters,
                            },
                        ],
                    },
                    volumeResolution: 0,
                    withAggregations: true,
                    limit: MAX_ISSUES,
                }

                const response = await api.query(query)

                return response.results.map(
                    (issue): MaxErrorTrackingIssuePreview => ({
                        id: issue.id,
                        name: issue.name,
                        description: issue.description,
                        library: issue.library,
                        status: issue.status,
                        occurrences: issue.aggregations?.occurrences ?? 0,
                        sessions: issue.aggregations?.sessions ?? 0,
                        users: issue.aggregations?.users ?? 0,
                        first_seen: issue.first_seen,
                        last_seen: issue.last_seen,
                    })
                )
            },
        },
    })),

    reducers({
        // The banner shows its own copy rather than the raw failure, so only the fact is kept.
        issuesFailed: [
            false,
            {
                loadIssues: () => false,
                loadIssuesFailure: () => true,
            },
        ],

        selectedScope: [
            null as TraceErrorsScope | null,
            {
                setScope: (_, { scope }) => scope,
            },
        ],
    }),

    selectors({
        // Most precise first, so a trace that carries every id opens on the span that threw.
        availableScopes: [
            () => [(_, props: TraceErrorsLogicProps) => props],
            (props: TraceErrorsLogicProps): TraceErrorsScope[] => {
                const traceId = usableId(props.traceId)
                const spanId = usableId(props.spanId)
                const scopes: TraceErrorsScope[] = []
                if (traceId && spanId) {
                    scopes.push('span')
                }
                if (traceId) {
                    scopes.push('trace')
                }
                if (props.sessionId) {
                    scopes.push('session')
                }
                return scopes
            },
        ],

        // The user's own pick wins, then the scope the caller asked for, then the most precise the
        // trace offers. A badge names the tier it counted, so the tab lists what the badge claimed
        // rather than a narrower scope the badge already ruled out.
        effectiveScope: [
            (s) => [s.availableScopes, s.selectedScope, (_, props: TraceErrorsLogicProps) => props.initialScope],
            (
                availableScopes: TraceErrorsScope[],
                selectedScope: TraceErrorsScope | null,
                initialScope: TraceErrorsScope | null
            ): TraceErrorsScope | null =>
                [selectedScope, initialScope].find((scope) => scope && availableScopes.includes(scope)) ??
                availableScopes[0] ??
                null,
        ],
    }),

    listeners(({ actions }) => ({
        setScope: () => {
            actions.loadIssues()
        },
    })),

    afterMount(({ actions }) => {
        actions.loadIssues()
    }),
])
