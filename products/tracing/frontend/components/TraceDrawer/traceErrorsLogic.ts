import { MakeLogicType, afterMount, kea, key, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'

import { MaxErrorTrackingIssuePreview } from '~/queries/schema/schema-assistant-error-tracking'
import { ErrorTrackingIssue, ErrorTrackingQuery, NodeKind } from '~/queries/schema/schema-general'
import { FilterLogicalOperator, PropertyFilterType, PropertyOperator } from '~/types'

import { sessionErrorsWindow } from '../../sessionErrors'

// The issues limit is the same one the Logs product's Related errors surface uses. A session with
// more issues than this is already past the point where a list helps.
const MAX_ISSUES = 100

export interface TraceErrorsLogicProps {
    traceId: string
    /** Trace start, which anchors the window the exceptions must fall in. */
    timestamp: string | null
    sessionId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceErrorsLogicValues {
    sessionIssues: MaxErrorTrackingIssuePreview[]
    sessionIssuesError: string | null
    sessionIssuesLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceErrorsLogicActions {
    loadSessionIssues: () => any
    loadSessionIssuesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSessionIssuesSuccess: (
        sessionIssues: MaxErrorTrackingIssuePreview[],
        payload?: any
    ) => {
        sessionIssues: MaxErrorTrackingIssuePreview[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceErrorsLogicMeta {
    key: string
}

export type traceErrorsLogicType = MakeLogicType<
    traceErrorsLogicValues,
    traceErrorsLogicActions,
    TraceErrorsLogicProps,
    traceErrorsLogicMeta
>

// The error tracking issues the open trace's session hit around the time the trace ran. The join
// is the session, not the trace, because an exception event only carries a trace id when the SDK
// propagated one. So these issues co-occurred with the trace; they were not necessarily caused
// by it.
export const traceErrorsLogic = kea<traceErrorsLogicType>([
    props({} as TraceErrorsLogicProps),
    key((props) => props.traceId),
    path((key) => ['products', 'tracing', 'frontend', 'components', 'TraceDrawer', 'traceErrorsLogic', key]),

    loaders(({ props }) => ({
        sessionIssues: {
            __default: [] as MaxErrorTrackingIssuePreview[],
            loadSessionIssues: async (): Promise<MaxErrorTrackingIssuePreview[]> => {
                const range = sessionErrorsWindow(props.timestamp ? [props.timestamp] : [])
                if (!range) {
                    return []
                }

                const query: ErrorTrackingQuery = {
                    kind: NodeKind.ErrorTrackingQuery,
                    orderBy: 'last_seen',
                    dateRange: { date_from: range.from, date_to: range.to },
                    filterGroup: {
                        type: FilterLogicalOperator.And,
                        values: [
                            {
                                type: FilterLogicalOperator.And,
                                values: [
                                    {
                                        type: PropertyFilterType.Event,
                                        key: '$session_id',
                                        value: props.sessionId,
                                        operator: PropertyOperator.Exact,
                                    },
                                ],
                            },
                        ],
                    },
                    volumeResolution: 0,
                    withAggregations: true,
                    limit: MAX_ISSUES,
                }

                const response = await api.query(query)
                const issues = response.results as ErrorTrackingIssue[]

                return issues.map(
                    (issue): MaxErrorTrackingIssuePreview => ({
                        id: issue.id,
                        name: issue.name,
                        description: issue.description,
                        library: issue.library,
                        status: issue.status,
                        occurrences: issue.aggregations?.occurrences ?? 0,
                        sessions: issue.aggregations?.sessions ?? 0,
                        users: issue.aggregations?.users ?? 0,
                        first_seen: issue.first_seen,
                        last_seen: issue.last_seen,
                    })
                )
            },
        },
    })),

    reducers({
        sessionIssuesError: [
            null as string | null,
            {
                loadSessionIssues: () => null,
                loadSessionIssuesFailure: (_, { error }) => error || 'Failed to load errors for this session',
            },
        ],
    }),

    afterMount(({ actions }) => {
        actions.loadSessionIssues()
    }),
])
