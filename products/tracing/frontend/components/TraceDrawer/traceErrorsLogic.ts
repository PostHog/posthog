import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'

import { MaxErrorTrackingIssuePreview } from '~/queries/schema/schema-assistant-error-tracking'
import { ErrorTrackingQuery, NodeKind } from '~/queries/schema/schema-general'
import { AnyPropertyFilter, FilterLogicalOperator, PropertyFilterType, PropertyOperator } from '~/types'

import { type ErrorScope, sessionErrorsWindow, traceErrorsWindow, usableId } from '../../errorCorrelation'

// The issues limit is the same one the Logs product's Related errors surface uses. A trace with
// more issues than this is already past the point where a list helps.
const MAX_ISSUES = 100

/** Which ids the listed issues are matched on, in falling order of confidence. */
export type TraceErrorsScope = ErrorScope

export interface TraceErrorsLogicProps {
    traceId: string
    /** The inspected span, which the span scope matches on. Null when no span is anchored. */
    spanId: string | null
    /**
     * Trace start, which anchors the window the exceptions must fall in. The trace anchors it
     * rather than the inspected span, so walking the waterfall does not re-ask a question whose
     * answer only moves by the trace's own duration.
     */
    timestamp: string | null
    /** The trace's session, or null when the spans resolve to no single session. */
    sessionId: string | null
    /** The scope to open on, when the caller named one. Null falls back to the most precise. */
    initialScope: TraceErrorsScope | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceErrorsLogicValues {
    availableScopes: TraceErrorsScope[]
    effectiveScope: TraceErrorsScope | null
    issues: MaxErrorTrackingIssuePreview[]
    issuesFailed: boolean
    issuesLoading: boolean
    selectedScope: TraceErrorsScope | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
