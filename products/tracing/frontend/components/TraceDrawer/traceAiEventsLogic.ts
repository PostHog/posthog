import { MakeLogicType, connect, kea, key, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { subscriptions } from 'kea-subscriptions'

import { FEATURE_FLAGS } from 'lib/constants'
import { type FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { teamLogic } from 'scenes/teamLogic'

import type { TraceAiEvent } from '../../aiEventSpans'
import { usableId } from '../../errorCorrelation'
import { tracingSpansTraceAiEventsRetrieve } from '../../generated/api'
import type { _TracingTraceAiEventsResponseApi } from '../../generated/api.schemas'

export interface TraceAiEventsLogicProps {
    traceId: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceAiEventsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentTeamId: number | null // teamLogic
    aiEventsResponse: _TracingTraceAiEventsResponseApi
    aiEventsResponseLoading: boolean
    aiEventsEnabled: boolean
    aiEvents: TraceAiEvent[]
    hasMoreAiEvents: boolean
    aiEventsLimit: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceAiEventsLogicActions {
    loadAiEvents: () => any
    loadAiEventsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAiEventsSuccess: (
        aiEventsResponse: _TracingTraceAiEventsResponseApi,
        payload?: any
    ) => {
        aiEventsResponse: _TracingTraceAiEventsResponseApi
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface traceAiEventsLogicMeta {
    key: string
}

export type traceAiEventsLogicType = MakeLogicType<
    traceAiEventsLogicValues,
    traceAiEventsLogicActions,
    TraceAiEventsLogicProps,
    traceAiEventsLogicMeta
>

const EMPTY_RESPONSE: _TracingTraceAiEventsResponseApi = { results: [], has_more: false, limit: 0 }

// The events half of the trace-to-AI-events join. The spans and the AI events sit on different
// ClickHouse clusters, so the backend cannot join them in one query; this fetches the events by
// trace id and the drawer places them on the waterfall by time.
export const traceAiEventsLogic = kea<traceAiEventsLogicType>([
    props({} as TraceAiEventsLogicProps),
    key((props) => props.traceId ?? ''),
    path((key) => ['products', 'tracing', 'frontend', 'components', 'TraceDrawer', 'traceAiEventsLogic', key]),

    connect(() => ({
        values: [teamLogic, ['currentTeamId'], featureFlagLogic, ['featureFlags']],
    })),

    loaders(({ props, values }) => ({
        aiEventsResponse: {
            __default: EMPTY_RESPONSE,
            loadAiEvents: async (): Promise<_TracingTraceAiEventsResponseApi> => {
                const traceId = usableId(props.traceId)
                const teamId = values.currentTeamId
                if (!values.featureFlags[FEATURE_FLAGS.TRACING_AI_EVENTS] || !traceId || teamId === null) {
                    return EMPTY_RESPONSE
                }
                return await tracingSpansTraceAiEventsRetrieve(String(teamId), traceId)
            },
        },
    })),

    selectors({
        aiEventsEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TRACING_AI_EVENTS],
        ],
        aiEvents: [
            (s) => [s.aiEventsResponse],
            (response: _TracingTraceAiEventsResponseApi): TraceAiEvent[] => response.results,
        ],
        hasMoreAiEvents: [
            (s) => [s.aiEventsResponse],
            (response: _TracingTraceAiEventsResponseApi): boolean => response.has_more,
        ],
        aiEventsLimit: [
            (s) => [s.aiEventsResponse],
            (response: _TracingTraceAiEventsResponseApi): number => response.limit,
        ],
    }),

    subscriptions(({ actions }) => ({
        // Runs on mount and again when the flag turns on, because on a cold page load the flag can
        // arrive from posthog-js after the trace has loaded.
        aiEventsEnabled: (enabled: boolean) => {
            if (enabled) {
                actions.loadAiEvents()
            }
        },
    })),
])
