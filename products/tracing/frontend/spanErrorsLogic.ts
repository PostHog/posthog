const MAX_IDS_PER_LOOKUP = tracingSpansErrorCountsCreateBodySpanIdsMax

// A kea breakpoint cancels a superseded lookup, and the one that survives asks about every id
// still unanswered, so this wait coalesces fast paging into a single query.
const LOOKUP_DEBOUNCE_MS = 300

// One shared instance, so the selectors below keep their identity while the feature is off.
const NO_SESSIONS: Map<string, string> = new Map()

/** Which join produced a row's count. The badge says a different thing for each. */
export type SpanErrorTier = ErrorScope

export interface SpanErrorBadge {
    tier: SpanErrorTier
    count: number
    /**
     * The session's own total, when the row matched on a narrower tier. It is a separate count
     * over a separate set, not a remainder: the session query matches `$session_id` and the trace
     * query matches `$trace_id`, so a backend exception can be in one and not the other.
     */
    alsoInSession?: number
}

export interface SpanErrorCounts {
    trace: Record<string, number>
    span: Record<string, number>
    session: Record<string, number>
}

type ExactCounts = Pick<SpanErrorCounts, 'trace' | 'span'>

