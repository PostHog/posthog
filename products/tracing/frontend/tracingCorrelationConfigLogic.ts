import { MakeLogicType, afterMount, connect, kea, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import { teamLogic } from 'scenes/teamLogic'

import type { PatchedTeamTracingConfigApi, TeamTracingConfigApi } from 'products/tracing/frontend/generated/api.schemas'

// Mirrors the backend defaults in products/tracing/backend/models.py — the same convention
// the Logs product uses (https://posthog.com/docs/logs/link-session-replay). Used as the
// pre-load fallback before `tracing_config` resolves.
export const DEFAULT_TRACING_DISTINCT_ID_ATTRIBUTE_KEYS = ['posthogDistinctId']

// Mirrors the backend default in products/tracing/backend/models.py. Ordered: session ID
// detection checks keys in list order and the first match wins.
export const DEFAULT_TRACING_SESSION_ID_ATTRIBUTE_KEYS = ['sessionId']

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingCorrelationConfigLogicValues {
    currentTeamId: number | null // teamLogic
    configuredDistinctIdKeys: string[] | undefined
    configuredSessionIdKeys: string[] | undefined
    tracingConfig: TeamTracingConfigApi | null
    tracingConfigLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingCorrelationConfigLogicActions {
    loadTracingConfig: () => any
    loadTracingConfigFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTracingConfigSuccess: (
        tracingConfig: TeamTracingConfigApi,
        payload?: any
    ) => {
        tracingConfig: TeamTracingConfigApi
        payload?: any
    }
    updateTracingConfig: (patch: PatchedTeamTracingConfigApi) => PatchedTeamTracingConfigApi
    updateTracingConfigFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    updateTracingConfigSuccess: (
        tracingConfig: TeamTracingConfigApi,
        payload?: PatchedTeamTracingConfigApi
    ) => {
        tracingConfig: TeamTracingConfigApi
        payload?: PatchedTeamTracingConfigApi
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingCorrelationConfigLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        configuredDistinctIdKeys: (tracingConfig: TeamTracingConfigApi | null) => string[] | undefined
        configuredSessionIdKeys: (tracingConfig: TeamTracingConfigApi | null) => string[] | undefined
    }
}

export type tracingCorrelationConfigLogicType = MakeLogicType<
    tracingCorrelationConfigLogicValues,
    tracingCorrelationConfigLogicActions,
    Record<string, any>,
    tracingCorrelationConfigLogicMeta
>

export const tracingCorrelationConfigLogic = kea<tracingCorrelationConfigLogicType>([
    path(['products', 'tracing', 'frontend', 'tracingCorrelationConfigLogic']),
    connect({ values: [teamLogic, ['currentTeamId']] }),
    loaders(({ values }) => ({
        tracingConfig: [
            null as TeamTracingConfigApi | null,
            {
                // The flat /api/projects/:team_id/ route is the canonical per-environment one
                // (same as logsConfigLogic). The generated client only exposes the nested
                // /api/projects/:pid/environments/:id/ variant, whose viewset rejects every
                // request, so these URLs are deliberately hand-built.
                loadTracingConfig: async (): Promise<TeamTracingConfigApi> => {
                    // nosemgrep: prefer-codegen-api
                    return await api.get(`api/projects/${values.currentTeamId}/tracing_config/`)
                },
                updateTracingConfig: async (patch: PatchedTeamTracingConfigApi): Promise<TeamTracingConfigApi> => {
                    // nosemgrep: prefer-codegen-api
                    return await api.update(`api/projects/${values.currentTeamId}/tracing_config/`, patch)
                },
            },
        ],
    })),
    selectors({
        // Undefined until tracing_config resolves — distinct-id detection falls back to its
        // built-in convention list (which contains the default) in the meantime.
        configuredDistinctIdKeys: [
            (s) => [s.tracingConfig],
            (tracingConfig: TeamTracingConfigApi | null): string[] | undefined =>
                tracingConfig?.tracing_distinct_id_attribute_keys,
        ],
        // Undefined until tracing_config resolves — session detection falls back to its
        // built-in convention list (which contains the default) in the meantime.
        configuredSessionIdKeys: [
            (s) => [s.tracingConfig],
            (tracingConfig: TeamTracingConfigApi | null): string[] | undefined =>
                tracingConfig?.tracing_session_id_attribute_keys,
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadTracingConfig()
    }),
])
