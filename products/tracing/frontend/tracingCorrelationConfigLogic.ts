export type tracingCorrelationConfigLogicType = MakeLogicType<
    tracingCorrelationConfigLogicValues,
    tracingCorrelationConfigLogicActions,
    Record<string, any>,
    tracingCorrelationConfigLogicMeta
>

export const tracingCorrelationConfigLogic = kea<tracingCorrelationConfigLogicType>([
    path(['products', 'tracing', 'frontend', 'tracingCorrelationConfigLogic']),
    connect({ values: [teamLogic, ['currentTeamId'], featureFlagLogic, ['featureFlags']] }),
    loaders(({ values }) => ({
        tracingConfig: [
            null as TeamTracingConfigApi | null,
            {
                // The flat /api/projects/:team_id/ route is the canonical per-environment one
                // (same as logsConfigLogic). The generated client only exposes the nested
                // /api/projects/:pid/environments/:id/ variant, whose viewset rejects every
                // request, so these URLs are deliberately hand-built.
                loadTracingConfig: async (): Promise<TeamTracingConfigApi> => {
                    // nosemgrep: prefer-codegen-api
                    return await api.get(`api/projects/${values.currentTeamId}/tracing_config/`)
                },
                updateTracingConfig: async (patch: PatchedTeamTracingConfigApi): Promise<TeamTracingConfigApi> => {
                    // nosemgrep: prefer-codegen-api
                    return await api.update(`api/projects/${values.currentTeamId}/tracing_config/`, patch)
                },
            },
        ],
    })),
    selectors({
        // Undefined until tracing_config resolves — distinct-id detection falls back to its
        // built-in convention list (which contains the default) in the meantime.
        configuredDistinctIdKeys: [
            (s) => [s.tracingConfig],
            (tracingConfig: TeamTracingConfigApi | null): string[] | undefined =>
                tracingConfig?.tracing_distinct_id_attribute_keys,
        ],
        // Undefined until tracing_config resolves — session detection falls back to its
        // built-in convention list (which contains the default) in the meantime.
        configuredSessionIdKeys: [
            (s) => [s.tracingConfig],
            (tracingConfig: TeamTracingConfigApi | null): string[] | undefined =>
                tracingConfig?.tracing_session_id_attribute_keys,
        ],
        // Single owner of the "link spans to persons and session replay?" rule, so the drawer
        // header and the span attribute table cannot drift apart.
        correlationLinksEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TRACING_SESSION_PERSON_LINKS],
        ],
        // Single owner of the "badge spans whose session hit errors?" rule, for the span list
        // badge and the trace drawer's Errors tab. Error Tracking viewer access is required as well
        // as the flag, because the counts and the issues are that product's data. The endpoints
        // behind both refuse a caller without it, so this gate is what keeps those surfaces from
        // rendering a refusal as an error state.
        sessionErrorBadgesEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean =>
                !!featureFlags[FEATURE_FLAGS.TRACING_SPAN_ERROR_BADGES] &&
                userHasAccess(AccessControlResourceType.ErrorTracking, AccessControlLevel.Viewer),
        ],
        // This config only feeds correlation surfaces, so it is only worth a request when one of
        // them is on. The error badges resolve a session from the same configured keys, so a team
        // that renamed those keys needs the config loaded for the badges alone.
        correlationConfigNeeded: [
            (s) => [s.correlationLinksEnabled, s.sessionErrorBadgesEnabled],
            (correlationLinksEnabled: boolean, sessionErrorBadgesEnabled: boolean): boolean =>
                correlationLinksEnabled || sessionErrorBadgesEnabled,
        ],
    }),
    subscriptions(({ actions, values }) => ({
        // A subscription rather than afterMount, because posthog-js can resolve the flags after
        // this logic mounts. Reading them once would leave the configured keys unloaded, and
        // session detection would silently fall back to the built-in convention list.
        correlationConfigNeeded: (needed: boolean) => {
            if (needed && !values.tracingConfig && !values.tracingConfigLoading) {
                actions.loadTracingConfig()
            }
        },
    })),
])
