// Per-instance viewer UI state: the trace drawer and the compare-flame modal. URL-free by
// design — the /tracing scene logic reads and writes this instance's state to sync the URL;
// an embedded viewer just never wires it up. Mirrors the logsViewerLogic boundary.
export const tracingViewerLogic = kea<tracingViewerLogicType>([
    props({ id: TRACING_SCENE_VIEWER_ID } as TracingViewerLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'tracing', 'frontend', 'tracingViewerLogic', key]),

    connect(({ id }: TracingViewerLogicProps) => ({
        values: [
            tracingDataLogic({ id }),
            [
                'spans',
                'traceSpans',
                'traceSpansLoading',
                'traceSpansLoadingMore',
                'traceSpansHasMore',
                'traceSpansLoadFailed',
                'traceLoadContext',
            ],
            tracingFiltersLogic({ id }),
            ['hasDeferredFilterRefresh'],
            tracingCorrelationConfigLogic,
            [
                'configuredDistinctIdKeys',
                'configuredSessionIdKeys',
                'correlationLinksEnabled',
                'sessionErrorBadgesEnabled',
            ],
            tracingConfigLogic,
            ['traceViewMode'],
        ],
        actions: [
            tracingDataLogic({ id }),
            ['loadTraceSpans', 'fetchSpanTree', 'fetchAggregation'],
            tracingFiltersLogic({ id }),
            ['updateComparisonWindows', 'refreshDeferredFilters'],
            traceViewLogic({ id: traceViewId(id) }),
            ['showTrace', 'selectSpan as selectViewSpan', 'setInspectorTab', 'enableSpanKeys', 'disableSpanKeys'],
            logsViewerModalLogic,
            ['openLogsViewerModal', 'closeLogsViewerModal'],
            sessionPlayerModalLogic,
            ['openSessionPlayer', 'closeSessionPlayer'],
        ],
    })),

    actions({
        openTrace: (
            traceId: string,
            options?: {
                spanId?: string | null
                ts?: string | null
                tab?: SpanInspectorTab | null
                errorsScope?: ErrorScope | null
            }
        ) => ({
            traceId: inApiCase(traceId),
            spanId: options?.spanId ? inApiCase(options.spanId) : null,
            ts: options?.ts ?? null,
            tab: options?.tab ?? null,
            errorsScope: options?.errorsScope ?? null,
        }),
        selectInspectorTab: (tab: SpanInspectorTab) => ({ tab }),
        selectSpan: (spanId: string | null) => ({ spanId: spanId ? inApiCase(spanId) : null }),
        closeTrace: true,
        toggleInspector: true,
        toggleFullscreen: true,
        openCompareFlame: (spanName: string, serviceName: string) => ({ spanName, serviceName }),
        closeCompareFlame: true,
    }),

    reducers({
        selectedTraceId: [
            null as string | null,
            {
                openTrace: (_, { traceId }) => traceId,
                closeTrace: () => null,
            },
        ],
        selectedSpanId: [
            null as string | null,
            {
                openTrace: (_, { spanId }) => spanId,
                selectSpan: (_, { spanId }) => spanId,
                closeTrace: () => null,
            },
        ],
        // Timestamp hint for the open trace — echoed into copy-links so cold loads can bound the
        // ClickHouse lookup (the spans table is time-keyed; OTel ids embed no timestamp).
        selectedTraceTs: [
            null as string | null,
            {
                openTrace: (_, { ts }) => ts,
                closeTrace: () => null,
            },
        ],
        // Which inspector tab the drawer shows. It lives here rather than in the drawer so a
        // caller can open a trace straight onto a tab, which the span list's error badge does.
        // Deliberately not a URL param, unlike the trace and span the drawer opens on. A shared
        // link carries which trace to read, and the reader picks their own tab from there, so a
        // reload lands on Attributes by design. Opening another trace while the drawer is up
        // keeps the tab, so a person reading the Logs tab row by row stays on it.
        // The scope the Errors tab opens on, when the caller named one.
        errorsScope: [
            null as ErrorScope | null,
            {
                openTrace: (_, { errorsScope }) => errorsScope,
                closeTrace: () => null,
            },
        ],
        inspectorTab: [
            'attributes' as SpanInspectorTab,
            {
                openTrace: (state, { tab }) => tab ?? state,
                closeTrace: () => 'attributes',
                selectInspectorTab: (_, { tab }) => tab,
                setInspectorTab: (_, { tab }) => tab,
            },
        ],
        inspectorOpen: [
            true,
            { persist: true },
            {
                toggleInspector: (open) => !open,
            },
        ],
        isFullscreen: [
            false,
            { persist: true },
            {
                toggleFullscreen: (fullscreen) => !fullscreen,
            },
        ],
        compareFlameSpanName: [
            null as string | null,
            {
                openCompareFlame: (_, { spanName }) => spanName,
                closeCompareFlame: () => null,
            },
        ],
        compareFlameServiceName: [
            null as string | null,
            {
                openCompareFlame: (_, { serviceName }) => serviceName,
                closeCompareFlame: () => null,
            },
        ],
    }),

    selectors({
        isTraceOpen: [
            (s) => [s.selectedTraceId],
            (selectedTraceId: string | null): boolean => selectedTraceId !== null,
        ],
        openTraceSpans: [
            (s) => [s.selectedTraceId, s.spans, s.traceSpans],
            (selectedTraceId: string | null, spans: Span[], traceSpans: Span[]): Span[] => {
                if (!selectedTraceId) {
                    return []
                }
                const filteredTraceSpans = traceSpans.filter((s) => s.trace_id === selectedTraceId)
                if (filteredTraceSpans.length > 0) {
                    return filteredTraceSpans
                }
                return spans.filter((s) => s.trace_id === selectedTraceId)
            },
        ],
        // The drawer's full-trace overlay should only show on the initial fetch — paging in more
        // spans (loadMoreTraceSpans) keeps the waterfall visible with its own bottom spinner.
        isLoadingFullTrace: [
            (s) => [s.traceSpansLoading, s.traceSpansLoadingMore],
            (traceSpansLoading: boolean, traceSpansLoadingMore: boolean): boolean =>
                traceSpansLoading && !traceSpansLoadingMore,
        ],
        // Only offer "load more" when the full-fetched spans for the open trace are what's displayed
        // — never for the small prefetch fallback, which is already the trace's complete span set.
        canLoadMoreTraceSpans: [
            (s) => [s.traceSpansHasMore, s.traceSpans, s.selectedTraceId],
            (traceSpansHasMore: boolean, traceSpans: Span[], selectedTraceId: string | null): boolean =>
                traceSpansHasMore &&
                !!selectedTraceId &&
                traceSpans.some((span: Span) => span.trace_id === selectedTraceId),
        ],
        // openTrace skips the fetch for a complete prefetch, so the raw flag can belong to a previous
        // attempt at this same trace (one a later, now-complete prefetch has since superseded).
        selectedTraceLoadFailed: [
            (s) => [s.traceSpansLoadFailed, s.traceLoadContext, s.selectedTraceId, s.spans],
            (
                traceSpansLoadFailed: boolean,
                traceLoadContext: { traceId: string; ts?: string | null } | null,
                selectedTraceId: string | null,
                spans: Span[]
            ): boolean =>
                traceSpansLoadFailed &&
                traceLoadContext?.traceId === selectedTraceId &&
                !!selectedTraceId &&
                !isCompletePrefetch(spans, selectedTraceId),
        ],
        // The person and session the open trace belongs to.
        traceIdentity: [
            (s) => [
                s.openTraceSpans,
                s.canLoadMoreTraceSpans,
                s.traceSpansLoading,
                s.configuredDistinctIdKeys,
                s.configuredSessionIdKeys,
                s.correlationLinksEnabled,
            ],
            (
                openTraceSpans: Span[],
                canLoadMoreTraceSpans: boolean,
                traceSpansLoading: boolean,
                configuredDistinctIdKeys: string[] | undefined,
                configuredSessionIdKeys: string[] | undefined,
                correlationLinksEnabled: boolean
            ): TraceIdentity => {
                // The flag guard runs before the scan, which reads every attribute of every span.
                if (!correlationLinksEnabled) {
                    return EMPTY_TRACE_IDENTITY
                }
                // Nothing while more spans can arrive, because a second, conflicting identity may
                // sit on a page that has not loaded, and the prefetch fallback shown during the
                // first fetch may itself be truncated.
                if (canLoadMoreTraceSpans || traceSpansLoading) {
                    return EMPTY_TRACE_IDENTITY
                }
                return resolveTraceIdentity(openTraceSpans, configuredDistinctIdKeys, configuredSessionIdKeys)
            },
        ],
        // The open trace's session for the Errors tab, which needs no person. It follows the badge
        // flag rather than the person and replay one, so the tab works for a team that has only the
        // badges. The gate also keeps the span scan off a team that has neither.
        //
        // It reads every span loaded so far, rather than waiting for a complete trace the way
        // `traceIdentity` does. A large trace pages in as the user scrolls the waterfall, and
        // waiting would leave the tab loading indefinitely. The badge that opens this tab already
        // resolves from one row, so the stricter rule would also make the two disagree. A later
        // page that carries a second session withdraws the answer rather than keeping a wrong one.
        traceSessionId: [
            (s) => [
                s.openTraceSpans,
                s.spans,
                s.selectedSpanId,
                s.configuredSessionIdKeys,
                s.sessionErrorBadgesEnabled,
            ],
            (
                openTraceSpans: Span[],
                spans: Span[],
                selectedSpanId: string | null,
                configuredSessionIdKeys: string[] | undefined,
                sessionErrorBadgesEnabled: boolean
            ): string | null => {
                if (!sessionErrorBadgesEnabled) {
                    return null
                }
                // The anchored span first, because a badge click opens the drawer on the row the
                // user pressed. Reading the whole trace instead would answer null for a trace that
                // touches two sessions, so a row that just showed a count would open a tab saying
                // the trace has no session.
                //
                // The full-trace fetch returns the earliest page of a large trace, which can omit
                // the anchored span. The row the user pressed is still in the list, so fall back to
                // it rather than resolving from a page that may carry another session.
                const findAnchored = (candidates: Span[]): Span | null =>
                    selectedSpanId ? (candidates.find((span) => span.span_id === selectedSpanId) ?? null) : null
                const anchored = findAnchored(openTraceSpans) ?? findAnchored(spans)
                const anchoredSessionId = anchored ? resolveSpanSessionId(anchored, configuredSessionIdKeys) : null
                return anchoredSessionId ?? resolveTraceSessionId(openTraceSpans, configuredSessionIdKeys)
            },
        ],
    }),

    listeners(({ actions, values, props }) => ({
        closeTrace: () => {
            actions.disableSpanKeys()
            // The attribute buttons in the drawer defer their query so the list doesn't reload
            // behind it — run it now that the drawer is closing.
            if (values.hasDeferredFilterRefresh) {
                actions.refreshDeferredFilters()
            }
        },
        openTrace: ({ traceId, ts, spanId }) => {
            actions.showTrace(spanId, values.inspectorTab)
            actions.enableSpanKeys(`[data-attr="${TRACE_DRAWER_DATA_ATTR}"]`, 'drawer')
            // pinned: analytics event and property names. The view persists across traces, so the view change event
            // alone cannot count how many traces people read as a call tree.
            posthog.capture('tracing trace opened', { view: values.traceViewMode })
            // Fetch the trace by id when the prefetch can be incomplete. A batch with no root span is a
            // cold link (no spans loaded) or an orphan trace, whose prefetch holds only the spans that
            // matched the list. A full prefetch batch (>= PREFETCH_SPANS) may be truncated.
            if (!isCompletePrefetch(values.spans, traceId)) {
                actions.loadTraceSpans({ traceId, ts })
            }
        },
        // The URL and the span tree each select spans, so each side passes on only a real change.
        selectSpan: ({ spanId }) => {
            if (spanId !== traceViewLogic({ id: traceViewId(props.id) }).values.selectedSpanId) {
                actions.selectViewSpan(spanId)
            }
        },
        selectViewSpan: ({ spanId }) => {
            if (spanId !== values.selectedSpanId) {
                actions.selectSpan(spanId)
            }
        },
        // These modals open over the drawer, so its keys must not step spans while one has focus.
        openLogsViewerModal: () => {
            actions.disableSpanKeys()
        },
        openSessionPlayer: () => {
            actions.disableSpanKeys()
        },
        closeLogsViewerModal: () => {
            if (values.isTraceOpen) {
                actions.enableSpanKeys(`[data-attr="${TRACE_DRAWER_DATA_ATTR}"]`, 'drawer')
            }
        },
        closeSessionPlayer: () => {
            if (values.isTraceOpen) {
                actions.enableSpanKeys(`[data-attr="${TRACE_DRAWER_DATA_ATTR}"]`, 'drawer')
            }
        },
        selectInspectorTab: ({ tab }) => {
            actions.setInspectorTab(tab)
        },
        openCompareFlame: ({ spanName, serviceName }) => {
            // The span and service names are the customer's own telemetry, so the event leaves them out.
            // pinned: analytics event name, so renaming it breaks the insights built on it
            posthog.capture('tracing compare flame opened')
            actions.fetchSpanTree({ spanName, serviceName })
        },
        updateComparisonWindows: () => {
            // The aggregation refetch on an overlay drag lives in tracingDataLogic; here we only
            // refresh the compare-flame modal (viewer UI) so it doesn't display stale windows.
            if (values.compareFlameSpanName && values.compareFlameServiceName) {
                actions.fetchSpanTree({
                    spanName: values.compareFlameSpanName,
                    serviceName: values.compareFlameServiceName,
                })
            }
        },
    })),
])
