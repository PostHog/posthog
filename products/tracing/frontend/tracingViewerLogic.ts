export function traceViewId(viewerId: string): string {
    return `tracing-viewer-${viewerId}`
}

// Mirrors the prefetch check in the `openTrace` listener: a batch with the trace's root span,
// under the cap, is already the trace's complete span set, so a fetch for it would be skipped.
// Also used by `selectedTraceLoadFailed` to tell a stale failure (from an earlier, differently
// shaped prefetch) apart from one that still describes what's about to be fetched.
function isCompletePrefetch(spans: Span[], traceId: string): boolean {
    const prefetchedSpans = spans.filter((s) => s.trace_id === traceId)
    return prefetchedSpans.some((s) => s.is_root_span) && prefetchedSpans.length < PREFETCH_SPANS
}

