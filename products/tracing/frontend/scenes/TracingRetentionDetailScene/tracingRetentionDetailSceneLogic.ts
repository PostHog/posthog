import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import { Scene } from 'scenes/sceneTypes'
import { teamLogic } from 'scenes/teamLogic'

import { Breadcrumb } from '~/types'

import {
    buildRetentionFormDefaults,
    logsRetentionFormLogic,
} from 'products/logs/frontend/components/LogsRetention/logsRetentionFormLogic'
import { LogsRetentionRuleApi } from 'products/logs/frontend/generated/api.schemas'
import { TRACES_RETENTION_PRODUCT } from 'products/tracing/frontend/components/TracingRetention/tracingRetentionProduct'
import { tracingRetentionSettingsUrl } from 'products/tracing/frontend/tracingRetentionSettingsUrl'

export interface TracingRetentionDetailSceneLogicProps {
    id: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingRetentionDetailSceneLogicValues {
    currentTeamId: number | null // teamLogic
    breadcrumbs: Breadcrumb[]
    rule: LogsRetentionRuleApi | null
    ruleLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingRetentionDetailSceneLogicActions {
    resetRetentionForm: (
        values?:
            | import('products/logs/frontend/components/LogsRetention/logsRetentionFormLogic').LogsRetentionFormType
            | undefined
    ) => {
        values?: import('products/logs/frontend/components/LogsRetention/logsRetentionFormLogic').LogsRetentionFormType
    } // logsRetentionFormLogic
    deleteRule: () => {
        value: true
    }
    loadRule: () => any
    loadRuleFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRuleSuccess: (
        rule: LogsRetentionRuleApi,
        payload?: any
    ) => {
        rule: LogsRetentionRuleApi
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingRetentionDetailSceneLogicMeta {
    key: string
}

export type tracingRetentionDetailSceneLogicType = MakeLogicType<
    tracingRetentionDetailSceneLogicValues,
    tracingRetentionDetailSceneLogicActions,
    TracingRetentionDetailSceneLogicProps,
    tracingRetentionDetailSceneLogicMeta
>

export const tracingRetentionDetailSceneLogic = kea<tracingRetentionDetailSceneLogicType>([
    path((key) => [
        'products',
        'tracing',
        'frontend',
        'scenes',
        'TracingRetentionDetailScene',
        'tracingRetentionDetailSceneLogic',
        key,
    ]),
    props({} as TracingRetentionDetailSceneLogicProps),
    key((props) => props.id),

    connect((props: TracingRetentionDetailSceneLogicProps) => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [
            logsRetentionFormLogic({
                rule: { id: props.id } as LogsRetentionRuleApi,
                product: TRACES_RETENTION_PRODUCT,
            }),
            ['resetRetentionForm'],
        ],
    })),

    actions({
        deleteRule: true,
    }),

    loaders(({ values, props }) => ({
        rule: [
            null as LogsRetentionRuleApi | null,
            {
                loadRule: async () => TRACES_RETENTION_PRODUCT.api.retrieve(String(values.currentTeamId), props.id),
            },
        ],
    })),

    selectors({
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: Scene.Tracing,
                    name: 'Tracing',
                    path: tracingRetentionSettingsUrl(),
                    iconType: 'tracing',
                },
                { key: Scene.TracingRetentionDetail, name: 'Retention rule', iconType: 'tracing' },
            ],
        ],
    }),

    listeners(({ actions, values, props }) => ({
        loadRuleSuccess: () => {
            if (values.rule) {
                actions.resetRetentionForm(buildRetentionFormDefaults(values.rule))
            }
        },
        deleteRule: async () => {
            try {
                await TRACES_RETENTION_PRODUCT.api.destroy(String(values.currentTeamId), props.id)
                lemonToast.success('Rule deleted')
                router.actions.push(tracingRetentionSettingsUrl())
            } catch (e: any) {
                lemonToast.error(e?.detail ?? e?.message ?? 'Failed to delete')
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadRule()
    }),
])
