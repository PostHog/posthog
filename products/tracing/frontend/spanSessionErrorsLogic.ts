// How many exceptions each session on the current page of spans hit, so a span row can say "this
// session hit errors" without the user opening the trace first. The count answers the session, not
// the span it sits on: an exception in the same session is co-occurring evidence, not a cause.
//
// The join is session id plus a time window rather than trace id, because an exception event only
// carries a trace id when the SDK propagated one.
//
// Only exceptions error tracking linked to an issue count: an event with no issue id failed
// ingestion parsing, so the Errors tab this badge opens can never list it. The two still disagree
// at the edges, because the tab anchors its window to the open trace rather than the whole page,
// caps at 100 issues, and resolves issues through fingerprint state this query cannot see.
export const spanSessionErrorsLogic = kea<spanSessionErrorsLogicType>([
    props({ id: TRACING_SCENE_VIEWER_ID } as SpanSessionErrorsLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'tracing', 'frontend', 'spanSessionErrorsLogic', key]),

    connect(({ id }: SpanSessionErrorsLogicProps) => ({
        values: [
            tracingDataLogic({ id }),
            ['listRows'],
            tracingCorrelationConfigLogic,
            ['configuredSessionIdKeys', 'sessionErrorBadgesEnabled'],
        ],
        actions: [tracingDataLogic({ id }), ['fetchSpansSuccess', 'fetchNextPageSuccess']],
    })),

    loaders(({ values }) => ({
        sessionErrorCounts: [
            {} as Record<string, number>,
            {
                loadSessionErrorCounts: async (
                    { reset }: { reset: boolean },
                    breakpoint
                ): Promise<Record<string, number>> => {
                    // A fresh query replaces the result set, so drop what the previous filters answered.
                    const known = reset ? {} : values.sessionErrorCounts
                    // hasOwn, not `in`: `in` walks the prototype chain, so a session id that
                    // collides with an Object member would read as already answered.
                    const sessionIds = values.sessionIdsInView.filter((sessionId) => !Object.hasOwn(known, sessionId))
                    // Read the range off the same snapshot the ids came from, before the debounce,
                    // so a page that empties mid-wait cannot leave the two disagreeing.
                    const range = sessionErrorsWindow(values.listRows.map((span) => span.timestamp))
                    if (sessionIds.length === 0 || !range) {
                        return known
                    }
                    await breakpoint(LOOKUP_DEBOUNCE_MS)

                    const response = await api.queryHogQL(
                        hogql`
                            SELECT properties.$session_id AS session_id, count() AS exceptions
                            FROM events
                            WHERE event = '$exception'
                              AND isNotNull(properties.$exception_issue_id)
                              AND timestamp >= ${range.from}
                              AND timestamp <= ${range.to}
                              AND properties.$session_id IN ${sessionIds}
                            GROUP BY session_id
                        `,
                        { scene: 'Tracing', productKey: 'tracing', name: 'tracing_session_error_counts' }
                    )
                    breakpoint()

                    // Every session looked up gets an entry, including the ones with no exceptions.
                    // That is what stops the next page re-asking about sessions already answered.
                    const counts: Record<string, number> = Object.fromEntries(
                        sessionIds.map((sessionId) => [sessionId, 0])
                    )
                    for (const [sessionId, exceptions] of (response.results ?? []) as [string, number][]) {
                        counts[sessionId] = Number(exceptions)
                    }
                    return { ...known, ...counts }
                },
            },
        ],
    })),

    selectors({
        sessionIdsInView: [
            (s) => [s.listRows, s.configuredSessionIdKeys],
            (listRows: Span[], configuredSessionIdKeys: string[] | undefined): string[] => {
                // One row at a time, not the trace's other loaded spans: the list prefetches a
                // capped number of spans per trace, so scanning them could resolve a session that
                // a span still to load contradicts.
                const sessionIds = listRows
                    .map((span) => resolveTraceSessionId([span], configuredSessionIdKeys))
                    .filter((sessionId): sessionId is string => !!sessionId)
                return Array.from(new Set(sessionIds)).slice(0, MAX_SESSIONS_PER_LOOKUP)
            },
        ],
    }),

    listeners(({ actions, values }) => {
        const lookUpNewSessions = (reset: boolean) => (): void => {
            if (values.sessionErrorBadgesEnabled) {
                actions.loadSessionErrorCounts({ reset })
            }
        }
        return {
            fetchSpansSuccess: lookUpNewSessions(true),
            fetchNextPageSuccess: lookUpNewSessions(false),
        }
    }),
])
