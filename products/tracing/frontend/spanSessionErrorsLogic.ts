// How many exceptions each session on the current page of spans hit, so a span row can say "this
// session hit errors" without the user opening the trace first. The count answers the session, not
// the span it sits on: an exception in the same session is co-occurring evidence, not a cause.
//
// The join is session id plus a time window rather than trace id, because an exception event only
// carries a trace id when the SDK propagated one.
//
// Only exceptions error tracking linked to an issue count: an event with no issue id failed
// ingestion parsing, so the Errors tab this badge opens can never list it. The two still disagree
// at the edges, because the tab anchors its window to the open trace rather than the whole page,
// caps at 100 issues, and resolves issues through fingerprint state this query cannot see.
export const spanSessionErrorsLogic = kea<spanSessionErrorsLogicType>([
    props({ id: TRACING_SCENE_VIEWER_ID } as SpanSessionErrorsLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'tracing', 'frontend', 'spanSessionErrorsLogic', key]),

    connect(({ id }: SpanSessionErrorsLogicProps) => ({
        values: [
            tracingDataLogic({ id }),
            ['listRows'],
            tracingCorrelationConfigLogic,
            ['configuredSessionIdKeys', 'sessionErrorBadgesEnabled'],
            teamLogic,
            ['currentTeamId'],
        ],
        actions: [
            tracingDataLogic({ id }),
            ['fetchSpansSuccess', 'fetchNextPageSuccess'],
            tracingCorrelationConfigLogic,
            ['loadTracingConfigSuccess'],
        ],
    })),

    loaders(({ values }) => ({
        sessionErrorCounts: [
            {} as Record<string, number>,
            {
                loadSessionErrorCounts: async (_: void, breakpoint): Promise<Record<string, number>> => {
                    // Wait first, so a lookup a faster page supersedes pays for none of the work
                    // below. Everything after this reads one snapshot, which keeps the ids and the
                    // range in agreement.
                    await breakpoint(LOOKUP_DEBOUNCE_MS)

                    const known = values.sessionErrorCounts
                    // hasOwn, not `in`, because `in` walks the prototype chain, so a session id
                    // that collides with an Object member would read as answered.
                    const sessionIds = values.sessionIdsInView.filter((sessionId) => !Object.hasOwn(known, sessionId))
                    if (sessionIds.length === 0) {
                        return known
                    }
                    // Only the rows this query asks about set the range. Taking every loaded row
                    // instead would widen it with each page and re-scan the time the earlier pages
                    // already covered.
                    const asked = new Set(sessionIds)
                    const sessionIdByRow = values.sessionIdByRow
                    const range = sessionErrorsWindow(
                        values.listRows
                            .filter((span) => {
                                const sessionId = sessionIdByRow.get(span.uuid)
                                return !!sessionId && asked.has(sessionId)
                            })
                            .map((span) => span.timestamp)
                    )
                    const teamId = values.currentTeamId
                    if (!range || !teamId) {
                        return known
                    }

                    // One request per cap-sized chunk, all in flight together, so a page with more
                    // sessions than one request allows is answered in one run rather than one chunk
                    // per debounce. The endpoint, not a HogQL query from here, because it checks the
                    // caller's Error Tracking access before it answers.
                    const chunks: string[][] = []
                    for (let start = 0; start < sessionIds.length; start += MAX_SESSIONS_PER_LOOKUP) {
                        chunks.push(sessionIds.slice(start, start + MAX_SESSIONS_PER_LOOKUP))
                    }
                    let responses: _TracingSessionErrorCountsResponseApi[]
                    try {
                        responses = await Promise.all(
                            chunks.map((chunk) =>
                                tracingSpansSessionErrorCountsCreate(String(teamId), {
                                    sessionIds: chunk,
                                    dateFrom: range.date_from,
                                    dateTo: range.date_to,
                                })
                            )
                        )
                    } catch {
                        // The badge is decoration on a list that stays useful without it, and a
                        // failure toast would repeat on every page. Leaving the sessions unanswered
                        // lets the next page ask again.
                        return known
                    }
                    breakpoint()

                    // Every session looked up gets an entry, including the ones with no exceptions.
                    // That is what stops the next page re-asking about sessions already answered.
                    const counts: Record<string, number> = Object.fromEntries(
                        sessionIds.map((sessionId) => [sessionId, 0])
                    )
                    for (const response of responses) {
                        for (const { session_id, exceptions } of response.results) {
                            // Only sessions this run asked about, so a stray row cannot mark a
                            // session answered before its own lookup.
                            if (Object.hasOwn(counts, session_id)) {
                                counts[session_id] = exceptions
                            }
                        }
                    }
                    return { ...known, ...counts }
                },
            },
        ],
    })),

    reducers({
        sessionErrorCounts: {
            // A fresh page answers different filters, so the counts stop applying the moment it
            // lands. Clearing here rather than inside the lookup keeps that true even when a next
            // page supersedes the lookup before its debounce elapses.
            fetchSpansSuccess: () => ({}),
        },
    }),

    selectors({
        // The one place a row's session is resolved, so the lookup and the badge can never read a
        // row differently.
        sessionIdByRow: [
            (s) => [s.listRows, s.configuredSessionIdKeys, s.sessionErrorBadgesEnabled],
            (
                listRows: Span[],
                configuredSessionIdKeys: string[] | undefined,
                sessionErrorBadgesEnabled: boolean
            ): Map<string, string> => {
                // The scan reads every attribute of every loaded row, so it must not run for a
                // team that does not have the badges.
                if (!sessionErrorBadgesEnabled) {
                    return NO_SESSIONS
                }
                const byRow = new Map<string, string>()
                for (const span of listRows) {
                    // One row at a time, not the trace's other loaded spans: the list prefetches a
                    // capped number of spans per trace, so scanning them could resolve a session
                    // that a span still to load contradicts.
                    const sessionId = resolveSpanSessionId(span, configuredSessionIdKeys)
                    if (sessionId) {
                        byRow.set(span.uuid, sessionId)
                    }
                }
                return byRow
            },
        ],

        sessionIdsInView: [
            (s) => [s.sessionIdByRow],
            (sessionIdByRow: Map<string, string>): string[] => Array.from(new Set(sessionIdByRow.values())),
        ],

        // What each row badges. A row is absent until its session is looked up and comes back with
        // exceptions, so an absent row is never a claim that its session is clean.
        errorCountByRow: [
            (s) => [s.sessionIdByRow, s.sessionErrorCounts],
            (sessionIdByRow: Map<string, string>, sessionErrorCounts: Record<string, number>): Map<string, number> => {
                const byRow = new Map<string, number>()
                for (const [uuid, sessionId] of sessionIdByRow) {
                    const count = sessionErrorCounts[sessionId]
                    if (count > 0) {
                        byRow.set(uuid, count)
                    }
                }
                return byRow
            },
        ],
    }),

    listeners(({ actions, values }) => {
        // Either way the lookup asks only about sessions with no count yet. A fresh page has none,
        // because the reducer above cleared them.
        const lookUpNewSessions = (): void => {
            if (values.sessionErrorBadgesEnabled) {
                actions.loadSessionErrorCounts()
            }
        }
        return {
            fetchSpansSuccess: lookUpNewSessions,
            fetchNextPageSuccess: lookUpNewSessions,
            // The configured session keys can land after the first page. Rows that resolved no
            // session under the built-in keys may resolve one now, and no page event follows.
            loadTracingConfigSuccess: lookUpNewSessions,
        }
    }),
])
