import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { dayjs } from 'lib/dayjs'
import { teamLogic } from 'scenes/teamLogic'

import { resolveSnoozeUntil } from 'products/alerts/frontend/utils'
import { platformAlertDestinationsLogic } from 'products/alerts_platform/frontend/destinations/platformAlertDestinationsLogic'
import { platformAlertsResetCreate, platformAlertsSnoozeCreate } from 'products/alerts_platform/frontend/generated/api'
import {
    PlatformAlertCreateDestinationApi,
    PlatformAlertConfigurationApi,
} from 'products/alerts_platform/frontend/generated/api.schemas'
import {
    PlatformAlertListLogicProps,
    platformAlertListLogic,
} from 'products/alerts_platform/frontend/platformAlertListLogic'

import { snoozeUntilError } from './tracesAlertUtils'

const TRACES_ALERT_LIST_PROPS: PlatformAlertListLogicProps = {
    sourceKind: 'traces',
    // Frozen analytics event names.
    analyticsEvents: { deleted: 'traces alert deleted', enabledToggled: 'traces alert enabled toggled' },
}

