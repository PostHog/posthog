import { MakeLogicType, afterMount, connect, kea, key, path, props } from 'kea'
import { forms } from 'kea-forms'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { ApiError } from 'lib/api'
import { teamLogic } from 'scenes/teamLogic'

import { UniversalFiltersGroup } from '~/types'

import {
    createPendingDestinations,
    platformAlertDestinationsLogic,
} from 'products/alerts_platform/frontend/destinations/platformAlertDestinationsLogic'
import { platformAlertsCreate, platformAlertsPartialUpdate } from 'products/alerts_platform/frontend/generated/api'
import {
    PatchedTracesPlatformAlertConfigurationEditApiSourceKind,
    PlatformAlertConfigurationApi,
    TracesPlatformAlertConfigurationCreateApiSourceKind,
} from 'products/alerts_platform/frontend/generated/api.schemas'

import { tracesAlertsLogic } from './tracesAlertsLogic'
import {
    NEW_ALERT_DESTINATIONS,
    TracesAlertFormErrors,
    TracesAlertFormType,
    buildFormDefaults,
    toWritePayload,
    validateForm,
} from './tracesAlertUtils'

export interface TracesAlertFormLogicProps {
    alert: PlatformAlertConfigurationApi | null
    /** What the traces viewer is filtered to, so a new alert starts from what the user is looking at. */
    viewerFilters?: { serviceNames: string[]; filterGroup: UniversalFiltersGroup }
    onSubmitSuccess?: () => void
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracesAlertFormLogicValues {
    currentTeamId: number | null // teamLogic
    alertForm: TracesAlertFormType
    alertFormChanged: boolean
    alertFormErrors: TracesAlertFormErrors
    alertFormHasErrors: boolean
    alertFormValidationErrors: TracesAlertFormErrors
    isAlertFormSubmitting: boolean
    showAlertFormErrors: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracesAlertFormLogicActions {
    loadAlerts: (_?: any) => any // tracesAlertsLogic
    resetAlertForm: (values?: TracesAlertFormType) => {
        values?: TracesAlertFormType
    }
    setAlertFormValue: (
        key: keyof TracesAlertFormType,
        value: any
    ) => {
        name: keyof TracesAlertFormType
        value: any
    }
    setAlertFormValues: (values: Partial<TracesAlertFormType>) => {
        values: Partial<TracesAlertFormType>
    }
    submitAlertForm: () => {
        value: true
    }
    touchAlertFormField: (key: keyof TracesAlertFormType) => {
        key: keyof TracesAlertFormType
    }
}

export type tracesAlertFormLogicType = MakeLogicType<
    tracesAlertFormLogicValues,
    tracesAlertFormLogicActions,
    TracesAlertFormLogicProps
>

function saveErrorMessage(error: unknown): string {
    const detail = (error as ApiError | undefined)?.detail
    return detail ? `Could not save the alert: ${detail}` : 'Could not save the alert. Try again.'
}

export const tracesAlertFormLogic = kea<tracesAlertFormLogicType>([
    path((key) => ['products', 'tracing', 'frontend', 'alerting', 'tracesAlertFormLogic', key]),
    props({} as TracesAlertFormLogicProps),
    key(({ alert }) => alert?.id ?? 'new'),

    connect({
        values: [teamLogic, ['currentTeamId']],
        actions: [tracesAlertsLogic, ['loadAlerts']],
    }),

    afterMount(({ actions, props }) => {
        // kea keeps a keyed logic's form between mounts, so a reopened modal starts from the saved alert.
        actions.resetAlertForm(buildFormDefaults(props.alert, props.viewerFilters))
    }),

    forms(({ props, actions, values }) => ({
        alertForm: {
            defaults: buildFormDefaults(props.alert, props.viewerFilters),
            errors: validateForm,
            submit: async (form) => {
                const projectId = String(values.currentTeamId)
                const payload = toWritePayload(form, props.alert)
                const properties = {
                    measure: form.measure,
                    group_by: form.groupBy,
                    window_minutes: form.windowMinutes,
                    service_count: form.serviceNames.length,
                }
                try {
                    if (props.alert) {
                        await platformAlertsPartialUpdate(projectId, props.alert.id, {
                            source_kind: PatchedTracesPlatformAlertConfigurationEditApiSourceKind.Traces,
                            ...payload,
                        })
                        posthog.capture('traces alert updated', properties)
                        lemonToast.success('Alert updated')
                    } else {
                        const created = await platformAlertsCreate(projectId, {
                            source_kind: TracesPlatformAlertConfigurationCreateApiSourceKind.Traces,
                            ...payload,
                        })
                        const pending =
                            platformAlertDestinationsLogic.findMounted(NEW_ALERT_DESTINATIONS)?.values
                                .pendingDestinations ?? []
                        const failed = await createPendingDestinations(projectId, created.id, pending)
                        posthog.capture('traces alert created', { ...properties, destination_count: pending.length })
                        if (failed > 0) {
                            lemonToast.warning(
                                `Alert created, but ${failed} of its destinations could not be added. Edit the alert to add them again.`
                            )
                        } else {
                            lemonToast.success('Alert created')
                        }
                    }
                } catch (error) {
                    lemonToast.error(saveErrorMessage(error))
                    throw error
                }
                actions.loadAlerts()
                props.onSubmitSuccess?.()
                return form
            },
        },
    })),
])
