import { MakeLogicType, connect, kea, listeners, path, selectors } from 'kea'

import {
    SavedView,
    SavedViewPayload,
    SavedViewsLogicProps,
    savedViewsLogic,
} from 'lib/components/SavedViews/savedViewsLogic'

import { TRACING_SCENE_VIEWER_ID, TracingFilters, tracingFiltersLogic } from '../tracingFiltersLogic'

// Subset of TracingFilters persisted in a saved view. Compare-mode and the dragged overlay windows
// are ephemeral UI state tied to on-screen sparkline data, so they're intentionally excluded.
export type SavedTracingFilters = Pick<
    TracingFilters,
    'dateRange' | 'serviceNames' | 'filterGroup' | 'orderBy' | 'orderDirection' | 'viewMode'
>

// Handwritten until `hogli build:openapi` generates `TracingViewApi` from TracingViewSerializer.
export interface TracingView {
    id: string
    short_id: string
    name: string
    filters: Partial<SavedTracingFilters>
    pinned: boolean
    created_at: string
    created_by: {
        first_name?: string
        email?: string
    } | null
    updated_at: string | null
}

export const TRACING_SAVED_VIEWS_LOGIC_PROPS: SavedViewsLogicProps = {
    key: 'tracing',
    endpoint: 'tracing/views',
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingViewsLogicValues {
    filters: TracingFilters // tracingFiltersLogic
    savePayload: SavedViewPayload
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingViewsLogicActions {
    loadView: (view: SavedView) => {
        view: SavedView
    } // savedViewsLogic
    setFilters: (filters: Partial<TracingFilters>) => {
        filters: Partial<TracingFilters>
    } // tracingFiltersLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tracingViewsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        savePayload: (filters: TracingFilters) => SavedViewPayload
    }
}

export type tracingViewsLogicType = MakeLogicType<
    tracingViewsLogicValues,
    tracingViewsLogicActions,
    Record<string, any>,
    tracingViewsLogicMeta
>

/** What a tracing saved view holds, on top of the shared saved views list in `savedViewsLogic`. */
export const tracingViewsLogic = kea<tracingViewsLogicType>([
    path(['products', 'tracing', 'frontend', 'savedViews', 'tracingViewsLogic']),

    // Saved views are a /tracing scene feature — always bind the scene's viewer instance.
    connect(() => ({
        values: [tracingFiltersLogic({ id: TRACING_SCENE_VIEWER_ID }), ['filters']],
        actions: [
            savedViewsLogic(TRACING_SAVED_VIEWS_LOGIC_PROPS),
            ['loadView'],
            tracingFiltersLogic({ id: TRACING_SCENE_VIEWER_ID }),
            ['setFilters'],
        ],
    })),

    selectors({
        savePayload: [
            (s) => [s.filters],
            (filters: TracingFilters): SavedViewPayload => {
                // Persist only the subset a view should restore — drop ephemeral compare-mode state.
                const { dateRange, serviceNames, filterGroup, orderBy, orderDirection, viewMode } = filters
                const savedFilters: SavedTracingFilters = {
                    dateRange,
                    serviceNames,
                    filterGroup,
                    orderBy,
                    orderDirection,
                    viewMode,
                }
                return { filters: savedFilters }
            },
        ],
    }),

    listeners(({ actions }) => ({
        loadView: ({ view }) => {
            actions.setFilters((view as TracingView).filters || {})
        },
    })),
])
