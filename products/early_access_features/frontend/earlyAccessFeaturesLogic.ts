export type earlyAccessFeaturesLogicType = MakeLogicType<
    earlyAccessFeaturesLogicValues,
    earlyAccessFeaturesLogicActions,
    Record<string, any>,
    earlyAccessFeaturesLogicMeta
>

export const earlyAccessFeaturesLogic = kea<earlyAccessFeaturesLogicType>([
    path(['products', 'earlyAccessFeatures', 'frontend', 'earlyAccessFeaturesLogic']),

    actions({
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        setFeatureAssignee: (id: EarlyAccessFeatureType['id'], assignee: EarlyAccessFeatureAssignee | null) => ({
            id,
            assignee,
        }),
        updateFeatureAssignee: (id: EarlyAccessFeatureType['id'], assignee: EarlyAccessFeatureAssignee | null) => ({
            id,
            assignee,
        }),
    }),

    loaders({
        earlyAccessFeatures: {
            __default: [] as EarlyAccessFeatureType[],
            loadEarlyAccessFeatures: async () => {
                const response = await api.earlyAccessFeatures.list()
                return response.results
            },
        },
        waitlistResponsesCount: {
            __default: {} as Record<string, number>,
            loadWaitlistResponsesCount: async (surveyIds: string) => {
                return await api.surveys.getResponsesCount(surveyIds)
            },
        },
    }),

    reducers({
        searchTerm: [
            '',
            {
                setSearchTerm: (_, { searchTerm }) => searchTerm,
            },
        ],
        earlyAccessFeatures: {
            setFeatureAssignee: (state, { id, assignee }) =>
                state.map((feature) => (feature.id === id ? { ...feature, assignee } : feature)),
        },
        waitlistResponsesCountFailed: [
            false,
            {
                loadWaitlistResponsesCount: () => false,
                loadWaitlistResponsesCountFailure: () => true,
            },
        ],
    }),

    selectors({
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: 'EarlyAccessFeatures',
                    name: 'Early access features',
                    path: urls.earlyAccessFeatures(),
                    iconType: 'early_access_feature',
                },
            ],
        ],

        filteredEarlyAccessFeatures: [
            (s) => [s.earlyAccessFeatures, s.searchTerm],
            (earlyAccessFeatures: EarlyAccessFeatureType[], searchTerm: string): EarlyAccessFeatureType[] => {
                return search(earlyAccessFeatures, searchTerm)
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        loadEarlyAccessFeaturesSuccess: ({ earlyAccessFeatures }) => {
            const surveyIds = earlyAccessFeatures.map(waitlistSurveyId).filter((id): id is string => id !== null)
            if (surveyIds.length > 0) {
                actions.loadWaitlistResponsesCount(surveyIds.join(','))
            }
        },
        updateFeatureAssignee: async ({ id, assignee }) => {
            // Read the value before the optimistic write so a failure reverts only this row,
            // without clobbering a concurrent edit on another row via a full-list reload.
            const previousAssignee = values.earlyAccessFeatures.find((feature) => feature.id === id)?.assignee ?? null
            actions.setFeatureAssignee(id, assignee)
            try {
                await api.earlyAccessFeatures.update(id, { assignee })
            } catch {
                lemonToast.error('Failed to update assignee')
                actions.setFeatureAssignee(id, previousAssignee)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadEarlyAccessFeatures()
    }),
])
