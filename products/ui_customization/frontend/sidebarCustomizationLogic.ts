export interface SidebarConfiguration {
    context: 'analytics_sidebar'
    defaults: AnalyticsSidebarApi
    storageKey: string
    resetEvent: string
    retrieve: (projectId: string) => Promise<AnalyticsSidebarApi>
    reset: (projectId: string) => Promise<AnalyticsSidebarApi>
    restore: (projectId: string, layout: AnalyticsSidebarLayoutApi) => Promise<AnalyticsSidebarApi>
}

export interface SidebarCustomizationProps {
    configuration: SidebarConfiguration
    projectId: string
    userId: string
}

type SidebarRequest =
    | { operation: 'load' }
    | { operation: 'reset'; previous: AnalyticsSidebarLayoutApi }
    | { operation: 'restore'; layout: AnalyticsSidebarLayoutApi }

