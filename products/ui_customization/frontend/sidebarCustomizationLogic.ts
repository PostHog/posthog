export type sidebarCustomizationLogicType = MakeLogicType<
    sidebarCustomizationLogicValues,
    sidebarCustomizationLogicActions,
    SidebarCustomizationProps,
    sidebarCustomizationLogicMeta
>

export const sidebarCustomizationLogic: LogicWrapper<sidebarCustomizationLogicType> =
    kea<sidebarCustomizationLogicType>([
        props({} as SidebarCustomizationProps),
        key(({ configuration, projectId, userId }) => `${userId}:${projectId}:${configuration.context}`),
        path((key) => ['products', 'uiCustomization', 'sidebarCustomizationLogic', key]),
        connect(() => ({
            values: [featureFlagLogic, ['featureFlags'], teamLogic, ['currentProjectId'], userLogic, ['user']],
        })),
        actions({
            loadSidebar: true,
            refreshSidebar: true,
            resetSidebar: (previous: CustomizationApi['layout']) => ({ previous }),
            restoreSidebar: (layout: CustomizationApi['layout']) => ({ layout }),
            requestSidebar: (request: SidebarRequest) => request,
            requestSidebarSuccess: (sidebar: CustomizationApi, payload?: SidebarRequest) => ({ sidebar, payload }),
            requestSidebarFailure: (error: string) => ({ error }),
            sidebarReadFailed: true,
            requestFinished: true,
            invalidateSession: true,
        }),
        reducers(({ props }) => ({
            savedSidebar: [
                null as CustomizationApi | null,
                {
                    persist: !!props.projectId && !!props.userId,
                    prefix: `${props.projectId}__${props.userId}__${props.configuration.context}__`,
                    storageKey: props.configuration.storageKey,
                },
                { requestSidebarSuccess: (_, { sidebar }) => sidebar },
            ],
            sidebarFailed: [
                false,
                { requestSidebar: () => false, requestSidebarSuccess: () => false, sidebarReadFailed: () => true },
            ],
            pendingRequests: [
                0,
                { requestSidebar: (state) => state + 1, requestFinished: (state) => Math.max(0, state - 1) },
            ],
            sessionActive: [true, { invalidateSession: () => false }],
        })),
        selectors(({ props }) => ({
            sidebarCustomizationEnabled: [
                (s) => [s.featureFlags, s.currentProjectId, s.user, s.sessionActive],
                (
                    flags: FeatureFlagsSet,
                    projectId: number | string,
                    user: UserType | null,
                    sessionActive: boolean
                ): boolean =>
                    sessionActive &&
                    !!props.userId &&
                    !!props.projectId &&
                    flags[FEATURE_FLAGS.UI_CUSTOMIZATION] === true &&
                    String(projectId) === props.projectId &&
                    user?.uuid === props.userId,
            ],
            shownSidebar: [
                (s) => [s.savedSidebar, s.sidebarCustomizationEnabled],
                (savedSidebar: CustomizationApi | null, enabled: boolean): CustomizationApi =>
                    enabled ? (savedSidebar ?? props.configuration.defaults) : props.configuration.defaults,
            ],
            sidebarLayout: [
                (s) => [s.shownSidebar],
                (sidebar: CustomizationApi): CustomizationApi['layout'] => sidebar.layout,
            ],
            sidebarCustomized: [(s) => [s.shownSidebar], (sidebar: CustomizationApi): boolean => sidebar.customized],
            sidebarLoading: [(s) => [s.pendingRequests], (pending: number): boolean => pending > 0],
        })),
        listeners(({ actions, asyncActions, cache, values, props }) => ({
            [userLogic.actionTypes.logout]: () => actions.invalidateSession(),
            // PostHog AI can save while its conversation is closed or the person is on another tab, and then no tool
            // event reaches this pane, so a pane that stays open reloads when the person comes back or moves on.
            [router.actionTypes.locationChanged]: () => actions.refreshSidebar(),
            refreshSidebar: () => {
                if (Date.now() - (cache.loadedAt ?? 0) >= SIDEBAR_REFRESH_INTERVAL_MS) {
                    actions.loadSidebar()
                }
            },
            [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
                const enabled = values.sidebarCustomizationEnabled
                if (enabled !== cache.enabled) {
                    cache.enabled = enabled
                    if (enabled) {
                        actions.loadSidebar()
                    }
                }
            },
            loadSidebar: () => {
                if (!values.sidebarCustomizationEnabled) {
                    return
                }
                if (cache.pendingWrites) {
                    cache.reloadAfterWrite = true
                    return
                }
                cache.loadedAt = Date.now()
                return asyncActions.requestSidebar({ operation: 'load' })
            },
            resetSidebar: ({ previous }) => {
                if (values.sidebarCustomizationEnabled) {
                    return asyncActions.requestSidebar({ operation: 'reset', previous })
                }
            },
            restoreSidebar: ({ layout }) => {
                if (values.sidebarCustomizationEnabled) {
                    return asyncActions.requestSidebar({ operation: 'restore', layout })
                }
            },
            requestSidebar: async (request: SidebarRequest) => {
                // A request owns a mount until reconciliation finishes, even when its pane leaves the screen.
                const release = sidebarCustomizationLogic(props).mount()
                const context = getContext()
                const generation = (cache.generation = (cache.generation ?? 0) + 1)
                const canApply = (): boolean => getContext() === context && values.sidebarCustomizationEnabled
                const isWrite = request.operation !== 'load'
                if (isWrite) {
                    cache.pendingWrites = (cache.pendingWrites ?? 0) + 1
                }
                try {
                    if (!canApply()) {
                        return
                    }
                    const run = (): Promise<CustomizationApi> =>
                        canApply() ? sendSidebarRequest(props, request) : Promise.resolve(props.configuration.defaults)
                    const response = isWrite ? (cache.writeTail ?? Promise.resolve()).then(run) : run()
                    if (isWrite) {
                        // A failed write must not prevent a later Reset or Undo from reaching the server.
                        cache.writeTail = response.catch(() => undefined)
                    }
                    const sidebar = await response
                    if (canApply() && generation === cache.generation) {
                        actions.requestSidebarSuccess(sidebar, request)
                        if (request.operation === 'reset') {
                            posthog.capture(props.configuration.resetEvent)
                            showResetToast(props, context, request.previous)
                        }
                    }
                } catch (error) {
                    if (canApply() && generation === cache.generation) {
                        if (request.operation === 'load') {
                            actions.sidebarReadFailed()
                        } else {
                            cache.reloadAfterWrite = true
                            toast.error({ title: WRITE_FAILURE_TITLES[request.operation] })
                        }
                        actions.requestSidebarFailure(String(error))
                    }
                } finally {
                    if (isWrite) {
                        cache.pendingWrites -= 1
                    }
                    if (getContext() === context) {
                        actions.requestFinished()
                        if (!cache.pendingWrites && cache.reloadAfterWrite) {
                            cache.reloadAfterWrite = false
                            actions.loadSidebar()
                        }
                        release()
                    }
                }
            },
        })),
        afterMount(({ actions, cache, values }) => {
            cache.enabled = values.sidebarCustomizationEnabled
            actions.loadSidebar()
            cache.disposables.add(
                () => {
                    const onReturn = (): void => {
                        if (document.visibilityState === 'visible') {
                            actions.refreshSidebar()
                        }
                    }
                    document.addEventListener('visibilitychange', onReturn)
                    window.addEventListener('focus', onReturn)
                    return () => {
                        document.removeEventListener('visibilitychange', onReturn)
                        window.removeEventListener('focus', onReturn)
                    }
                },
                'refreshOnReturn',
                { pauseOnPageHidden: false }
            )
        }),
    ])

function sendSidebarRequest(props: SidebarCustomizationProps, request: SidebarRequest): Promise<CustomizationApi> {
    const { configuration, projectId } = props
    const signal = AbortSignal.timeout(SIDEBAR_REQUEST_TIMEOUT_MS)
    switch (request.operation) {
        case 'reset':
            return configuration.reset(projectId, signal)
        case 'restore':
            return configuration.restore(projectId, request.layout, signal)
        default:
            return configuration.retrieve(projectId, signal)
    }
}

function showResetToast(
    props: SidebarCustomizationProps,
    context: ReturnType<typeof getContext>,
    previous: CustomizationApi['layout']
): void {
    toast.success({
        title: 'Sidebar reset to the default',
        action: {
            label: 'Undo',
            onClick: async () => {
                if (getContext() !== context) {
                    return
                }
                const instance = sidebarCustomizationLogic(props)
                const unmount = instance.mount()
                try {
                    if (instance.values.sidebarCustomizationEnabled) {
                        await instance.asyncActions.restoreSidebar(previous)
                    }
                } finally {
                    unmount()
                }
            },
        },
    })
}
