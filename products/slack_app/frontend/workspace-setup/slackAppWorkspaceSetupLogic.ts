export const slackAppWorkspaceSetupLogic = kea<slackAppWorkspaceSetupLogicType>([
    path((key) => ['products', 'slack_app', 'workspace-setup', 'slackAppWorkspaceSetupLogic', key]),
    props({} as SlackAppWorkspaceSetupLogicProps),
    key((props) => props.integrationId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        completeStep: (step: WorkspaceSetupStepKey) => ({ step }),
        skipStep: (step: WorkspaceSetupStepKey) => ({ step }),
        stepFailed: (step: WorkspaceSetupStepKey, error: string) => ({ step, error }),
        selectProject: (integrationId: number) => ({ integrationId }),
        setSelectedChannelIds: (channelIds: string[]) => ({ channelIds }),
        setPostWelcome: (postWelcome: boolean) => ({ postWelcome }),
        openSlackClicked: true,
    }),
    loaders(({ props, values }) => ({
        setup: [
            null as SlackAppWorkspaceSetupApi | null,
            {
                loadSetup: async () => {
                    return await slackAppWorkspaceSetupRetrieve(
                        String(values.currentTeamId),
                        String(props.integrationId),
                        {
                            entry: props.entry ?? 'other',
                        }
                    )
                },
                saveDefaultProject: async () => {
                    return await slackAppWorkspaceSetupDefaultProjectCreate(
                        String(values.currentTeamId),
                        String(props.integrationId),
                        { integration_id: values.selectedProjectIntegrationId }
                    )
                },
            },
        ],
        channelOptions: [
            null as SlackAppChannelOptionApi[] | null,
            {
                loadChannelOptions: async () => {
                    const response = await slackAppWorkspaceSetupChannelsRetrieve(
                        String(values.currentTeamId),
                        String(props.integrationId)
                    )
                    return response.channels
                },
            },
        ],
        joinResults: [
            null as SlackAppChannelJoinResultApi[] | null,
            {
                joinChannels: async () => {
                    const response = await slackAppWorkspaceSetupJoinChannelsCreate(
                        String(values.currentTeamId),
                        String(props.integrationId),
                        {
                            channel_ids: values.selectedChannelIds,
                            post_welcome: values.postWelcome && !!values.setup?.can_post_channel_welcome,
                        }
                    )
                    return response.results
                },
            },
        ],
    })),
    reducers(({ props }) => ({
        finishedSteps: [
            [] as WorkspaceSetupStepKey[],
            {
                completeStep: (state, { step }) => [...state, step],
                skipStep: (state, { step }) => [...state, step],
            },
        ],
        skippedSteps: [
            [] as WorkspaceSetupStepKey[],
            {
                skipStep: (state, { step }) => [...state, step],
            },
        ],
        // Fixed at the first load, so the progress bar still counts the steps that a save removes.
        initialSteps: [
            null as WorkspaceSetupStepKey[] | null,
            {
                loadSetupSuccess: (state, { setup }) => state ?? setup.steps,
            },
        ],
        selectedProjectIntegrationId: [
            props.integrationId,
            {
                selectProject: (_, { integrationId }) => integrationId,
            },
        ],
        selectedChannelIds: [
            [] as string[],
            {
                setSelectedChannelIds: (_, { channelIds }) => channelIds,
            },
        ],
        postWelcome: [
            true,
            {
                setPostWelcome: (_, { postWelcome }) => postWelcome,
            },
        ],
    })),
    selectors({
        steps: [
            (s) => [s.initialSteps],
            (initialSteps: WorkspaceSetupStepKey[] | null): WorkspaceSetupStepKey[] =>
                (initialSteps ?? []).filter((step) => WORKSPACE_SETUP_STEP_KEYS.includes(step)),
        ],
        currentStep: [
            (s) => [s.steps, s.finishedSteps],
            (steps: WorkspaceSetupStepKey[], finishedSteps: WorkspaceSetupStepKey[]): WorkspaceSetupStepKey | null =>
                steps.find((step) => !finishedSteps.includes(step)) ?? null,
        ],
        currentStepNumber: [
            (s) => [s.steps, s.currentStep],
            (steps: WorkspaceSetupStepKey[], currentStep: WorkspaceSetupStepKey | null): number =>
                currentStep ? steps.indexOf(currentStep) + 1 : steps.length,
        ],
        returnLink: [
            () => [(_, props) => props.returnTo],
            (returnTo: SlackSetupReturnTarget | undefined): SlackSetupReturnLink | null =>
                slackSetupReturnLink(returnTo),
        ],
        joinableChannels: [
            (s) => [s.channelOptions],
            (channelOptions: SlackAppChannelOptionApi[] | null): SlackAppChannelOptionApi[] =>
                (channelOptions ?? []).filter((channel) => !channel.is_member),
        ],
        joinedChannelNames: [
            (s) => [s.channelOptions],
            (channelOptions: SlackAppChannelOptionApi[] | null): string[] =>
                (channelOptions ?? []).filter((channel) => channel.is_member).map((channel) => channel.name),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        loadSetupSuccess: ({ setup }) => {
            if (setup.steps.includes('channels') && values.channelOptions === null) {
                actions.loadChannelOptions()
            }
            // pinned: analytics event and property names, renaming breaks dashboards
            posthog.capture('slack app workspace setup viewed', {
                ...setupEventProperties(props),
                steps: setup.steps,
            })
        },
        loadSetupFailure: () => {
            posthog.capture('slack app workspace setup load failed', setupEventProperties(props))
        },
        saveDefaultProjectSuccess: () => {
            actions.completeStep('default_project')
        },
        saveDefaultProjectFailure: ({ error }) => {
            actions.stepFailed('default_project', error)
        },
        loadChannelOptionsFailure: ({ error }) => {
            actions.stepFailed('channels', error)
        },
        joinChannelsFailure: ({ error }) => {
            actions.stepFailed('channels', error)
        },
        joinChannelsSuccess: ({ joinResults }) => {
            const failed = (joinResults ?? []).filter((result) => result.error)
            const names = new Map((values.channelOptions ?? []).map((channel) => [channel.id, channel.name]))
            if (failed.length > 0) {
                const failedNames = failed.map((result) => `#${names.get(result.channel_id) ?? result.channel_id}`)
                lemonToast.warning(
                    `PostHog couldn't join ${failedNames.join(', ')}. Invite it with /invite @PostHog in those channels.`
                )
                // Slack's refusals arrive in a successful response, so the loader's failure listener never sees them.
                actions.stepFailed('channels', [...new Set(failed.map((result) => result.error))].join(', '))
            }
            actions.completeStep('channels')
        },
        completeStep: ({ step }) => {
            posthog.capture('slack app workspace setup step completed', { ...setupEventProperties(props), step })
        },
        skipStep: ({ step }) => {
            posthog.capture('slack app workspace setup step skipped', { ...setupEventProperties(props), step })
        },
        stepFailed: ({ step, error }) => {
            posthog.capture('slack app workspace setup step failed', { ...setupEventProperties(props), step, error })
        },
        openSlackClicked: () => {
            posthog.capture('slack app workspace setup open slack clicked', {
                ...setupEventProperties(props),
                finished_steps: values.finishedSteps,
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSetup()
    }),
])
