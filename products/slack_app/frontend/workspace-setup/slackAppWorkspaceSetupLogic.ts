import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'

import { slackAppWorkspaceSetupDefaultProjectCreate, slackAppWorkspaceSetupRetrieve } from '../generated/api'
import type { SlackAppWorkspaceSetupApi } from '../generated/api.schemas'
import type { SlackSetupStepKeyEnumApi } from '../generated/api.schemas'

export type WorkspaceSetupStepKey = SlackAppWorkspaceSetupApi['steps'][number]

/** The steps this frontend can show. A key the backend sends that is not here is left out. */
export const WORKSPACE_SETUP_STEP_KEYS: WorkspaceSetupStepKey[] = ['ai_consent', 'default_project']

export interface SlackAppWorkspaceSetupLogicProps {
    integrationId: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface slackAppWorkspaceSetupLogicValues {
    currentTeamId: number | null // teamLogic
    currentStep: WorkspaceSetupStepKey | null
    currentStepNumber: number
    finishedSteps: WorkspaceSetupStepKey[]
    initialSteps: WorkspaceSetupStepKey[] | null
    pickedProjectIntegrationId: number | null
    savingDefaultProject: boolean
    selectedProjectIntegrationId: number
    setup: SlackAppWorkspaceSetupApi | null
    setupLoading: boolean
    skippedSteps: WorkspaceSetupStepKey[]
    steps: WorkspaceSetupStepKey[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface slackAppWorkspaceSetupLogicActions {
    completeStep: (step: WorkspaceSetupStepKey) => {
        step: SlackSetupStepKeyEnumApi
    }
    loadSetup: () => any
    loadSetupFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSetupSuccess: (
        setup: SlackAppWorkspaceSetupApi,
        payload?: any
    ) => {
        setup: SlackAppWorkspaceSetupApi
        payload?: any
    }
    openSlackClicked: () => {
        value: true
    }
    saveDefaultProject: () => any
    saveDefaultProjectFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    saveDefaultProjectSuccess: (
        setup: SlackAppWorkspaceSetupApi,
        payload?: any
    ) => {
        setup: SlackAppWorkspaceSetupApi
        payload?: any
    }
    selectProject: (integrationId: number) => {
        integrationId: number
    }
    skipStep: (step: WorkspaceSetupStepKey) => {
        step: SlackSetupStepKeyEnumApi
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface slackAppWorkspaceSetupLogicMeta {
    key: any
    __keaTypeGenInternalSelectorTypes: {
        steps: (initialSteps: any) => WorkspaceSetupStepKey[]
        currentStep: (steps: any, finishedSteps: any) => WorkspaceSetupStepKey | null
        currentStepNumber: (steps: any, currentStep: any) => number
        selectedProjectIntegrationId: (pickedProjectIntegrationId: any, arg: any) => number
    }
}

export type slackAppWorkspaceSetupLogicType = MakeLogicType<
    slackAppWorkspaceSetupLogicValues,
    slackAppWorkspaceSetupLogicActions,
    SlackAppWorkspaceSetupLogicProps,
    slackAppWorkspaceSetupLogicMeta
>

export const slackAppWorkspaceSetupLogic = kea<slackAppWorkspaceSetupLogicType>([
    path((key) => ['products', 'slack_app', 'workspace-setup', 'slackAppWorkspaceSetupLogic', key]),
    props({} as SlackAppWorkspaceSetupLogicProps),
    key((props) => props.integrationId),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        completeStep: (step: WorkspaceSetupStepKey) => ({ step }),
        skipStep: (step: WorkspaceSetupStepKey) => ({ step }),
        selectProject: (integrationId: number) => ({ integrationId }),
        openSlackClicked: true,
    }),
    loaders(({ props, values }) => ({
        setup: [
            null as SlackAppWorkspaceSetupApi | null,
            {
                loadSetup: async () => {
                    return await slackAppWorkspaceSetupRetrieve(
                        String(values.currentTeamId),
                        String(props.integrationId)
                    )
                },
                saveDefaultProject: async () => {
                    return await slackAppWorkspaceSetupDefaultProjectCreate(
                        String(values.currentTeamId),
                        String(props.integrationId),
                        { integration_id: values.selectedProjectIntegrationId }
                    )
                },
            },
        ],
    })),
    reducers({
        finishedSteps: [
            [] as WorkspaceSetupStepKey[],
            {
                completeStep: (state, { step }) => [...state, step],
                skipStep: (state, { step }) => [...state, step],
            },
        ],
        skippedSteps: [
            [] as WorkspaceSetupStepKey[],
            {
                skipStep: (state, { step }) => [...state, step],
            },
        ],
        // The first load fixes the step list. A save returns fewer steps, and the progress bar must
        // keep counting the steps the person already finished.
        initialSteps: [
            null as WorkspaceSetupStepKey[] | null,
            {
                loadSetupSuccess: (state, { setup }) => state ?? setup?.steps ?? null,
            },
        ],
        pickedProjectIntegrationId: [
            null as number | null,
            {
                selectProject: (_, { integrationId }) => integrationId,
            },
        ],
        savingDefaultProject: [
            false,
            {
                saveDefaultProject: () => true,
                saveDefaultProjectSuccess: () => false,
                saveDefaultProjectFailure: () => false,
            },
        ],
    }),
    selectors({
        steps: [
            (s) => [s.initialSteps],
            (initialSteps: WorkspaceSetupStepKey[] | null): WorkspaceSetupStepKey[] =>
                (initialSteps ?? []).filter((step) => WORKSPACE_SETUP_STEP_KEYS.includes(step)),
        ],
        currentStep: [
            (s) => [s.steps, s.finishedSteps],
            (steps: WorkspaceSetupStepKey[], finishedSteps: WorkspaceSetupStepKey[]): WorkspaceSetupStepKey | null =>
                steps.find((step) => !finishedSteps.includes(step)) ?? null,
        ],
        currentStepNumber: [
            (s) => [s.steps, s.currentStep],
            (steps: WorkspaceSetupStepKey[], currentStep: WorkspaceSetupStepKey | null): number =>
                currentStep ? steps.indexOf(currentStep) + 1 : steps.length,
        ],
        selectedProjectIntegrationId: [
            (s) => [s.pickedProjectIntegrationId, (_, props) => props.integrationId],
            (pickedProjectIntegrationId: number | null, integrationId: number): number =>
                pickedProjectIntegrationId ?? integrationId,
        ],
    }),
    listeners(({ actions, values, props }) => ({
        loadSetupSuccess: ({ setup }) => {
            // pinned: analytics event and property names, renaming breaks dashboards
            posthog.capture('slack app workspace setup viewed', {
                integration_id: props.integrationId,
                steps: setup?.steps ?? [],
            })
        },
        saveDefaultProjectSuccess: () => {
            actions.completeStep('default_project')
        },
        completeStep: ({ step }) => {
            posthog.capture('slack app workspace setup step completed', { integration_id: props.integrationId, step })
        },
        skipStep: ({ step }) => {
            posthog.capture('slack app workspace setup step skipped', { integration_id: props.integrationId, step })
        },
        openSlackClicked: () => {
            posthog.capture('slack app workspace setup open slack clicked', {
                integration_id: props.integrationId,
                finished_steps: values.finishedSteps,
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSetup()
    }),
])
