export const slackAppSettingsLogic = kea<slackAppSettingsLogicType>([
    path(['products', 'slack_app', 'frontend', 'settings', 'slackAppSettingsLogic']),
    connect(() => ({
        values: [integrationsLogic, ['slackIntegrations', 'integrationsLoading'], teamLogic, ['currentTeamId']],
        actions: [integrationsLogic, ['loadIntegrationsSuccess']],
    })),
    actions({
        selectIntegration: (integrationId: number) => ({ integrationId }),
        loadAll: true,
        openChannelModal: (channel: SlackAppChannelSettingsApi | null) => ({ channel }),
        closeChannelModal: true,
        setChannelDraft: (change: Partial<ChannelDraft>) => ({ change }),
        saveChannelDraft: true,
        removeChannel: (slackChannelId: string) => ({ slackChannelId }),
        setChannels: (channels: SlackAppChannelSettingsApi[]) => ({ channels }),
        setChannelSaving: (saving: boolean) => ({ saving }),
    }),
    reducers({
        pickedIntegrationId: [
            null as number | null,
            {
                selectIntegration: (_, { integrationId }) => integrationId,
            },
        ],
        channelDraft: [
            null as ChannelDraft | null,
            {
                openChannelModal: (_, { channel }) =>
                    channel
                        ? {
                              slack_channel_id: channel.slack_channel_id,
                              default_integration_id: channel.default_integration_id,
                              default_repository: channel.default_repository,
                              untagged_question_mode: channel.untagged_question_mode,
                          }
                        : EMPTY_DRAFT,
                setChannelDraft: (state, { change }) => (state ? { ...state, ...change } : state),
                closeChannelModal: () => null,
                selectIntegration: () => null,
            },
        ],
        isEditingChannel: [
            false,
            {
                openChannelModal: (_, { channel }) => channel !== null,
            },
        ],
        channelSaving: [
            false,
            {
                setChannelSaving: (_, { saving }) => saving,
            },
        ],
        channels: {
            setChannels: (_, { channels }) => channels,
            selectIntegration: () => null,
        },
        channelsLoadFailed: [
            false,
            {
                loadChannels: () => false,
                loadChannelsSuccess: () => false,
                loadChannelsFailure: () => true,
                selectIntegration: () => false,
            },
        ],
        // Another workspace's settings must not stay on screen, or stay editable, while the new ones load.
        settings: {
            selectIntegration: () => null,
        },
    }),
    loaders(({ values }) => ({
        settings: [
            null as SlackAppSettingsApi | null,
            {
                loadSettings: async (_: void, breakpoint) => {
                    if (values.selectedIntegrationId === null) {
                        return null
                    }
                    const response = await slackAppSettingsRetrieve(
                        String(values.currentTeamId),
                        String(values.selectedIntegrationId)
                    )
                    // A later load, after a workspace switch, replaces this response.
                    breakpoint()
                    return response
                },
                updatePersonalSettings: async (change: PatchedSlackAppPersonalSettingsUpdateApi) => {
                    const integrationId = values.selectedIntegrationId
                    if (integrationId === null) {
                        return values.settings
                    }
                    try {
                        const response = await slackAppSettingsPersonalPartialUpdate(
                            String(values.currentTeamId),
                            String(integrationId),
                            change
                        )
                        return integrationId === values.selectedIntegrationId ? response : values.settings
                    } catch (error: any) {
                        lemonToast.error(error?.detail ?? "Couldn't save your Slack settings. Try again.")
                        return values.settings
                    }
                },
            },
        ],
        channels: [
            null as SlackAppChannelSettingsApi[] | null,
            {
                loadChannels: async (_: void, breakpoint) => {
                    if (values.selectedIntegrationId === null) {
                        return null
                    }
                    const response = await slackAppSettingsChannelsRetrieve(
                        String(values.currentTeamId),
                        String(values.selectedIntegrationId)
                    )
                    // A later load, after a workspace switch, replaces this response.
                    breakpoint()
                    return response.channels
                },
            },
        ],
        repositoryOptions: [
            null as SlackAppRepositoryOptionsApi | null,
            {
                loadRepositoryOptions: async () => {
                    if (values.selectedIntegrationId === null) {
                        return null
                    }
                    return await slackAppSettingsRepositoriesRetrieve(
                        String(values.currentTeamId),
                        String(values.selectedIntegrationId)
                    )
                },
            },
        ],
    })),
    selectors({
        selectedIntegrationId: [
            (s) => [s.pickedIntegrationId, s.slackIntegrations],
            (pickedIntegrationId: number | null, slackIntegrations: IntegrationType[] | undefined): number | null =>
                pickedIntegrationId ?? slackIntegrations?.[0]?.id ?? null,
        ],
        // One change at a time, so two quick clicks can't save out of order.
        personalSettingsDisabledReason: [
            (s) => [s.settingsLoading],
            (settingsLoading: boolean): string | undefined => (settingsLoading ? 'Saving your last change' : undefined),
        ],
        selectedIntegration: [
            (s) => [s.selectedIntegrationId, s.slackIntegrations],
            (
                selectedIntegrationId: number | null,
                slackIntegrations: IntegrationType[] | undefined
            ): IntegrationType | null =>
                slackIntegrations?.find((integration) => integration.id === selectedIntegrationId) ?? null,
        ],
        channelSaveDisabledReason: [
            (s) => [s.channelDraft, s.isEditingChannel, s.channels],
            (
                channelDraft: ChannelDraft | null,
                isEditingChannel: boolean,
                channels: SlackAppChannelSettingsApi[] | null
            ): string | undefined => {
                if (!channelDraft?.slack_channel_id) {
                    return 'Select a channel'
                }
                // Saving an edited channel with every setting cleared removes its settings, so only a new channel needs one.
                if (isEditingChannel) {
                    return undefined
                }
                if ((channels ?? []).some((channel) => channel.slack_channel_id === channelDraft.slack_channel_id)) {
                    return 'This channel already has settings. Edit it in the list instead.'
                }
                return hasChannelSetting(channelDraft) ? undefined : 'Set at least one setting'
            },
        ],
        projectNames: [
            (s) => [s.settings],
            (settings: SlackAppSettingsApi | null): Record<number, string> =>
                Object.fromEntries(
                    (settings?.personal.project_options ?? []).map((option) => [
                        option.integration_id,
                        option.project_name,
                    ])
                ),
        ],
    }),
    listeners(({ actions, values }) => {
        const putChannel = async (slackChannelId: string, change: SlackAppChannelSettingsUpdateApi): Promise<void> => {
            const integrationId = values.selectedIntegrationId
            const saved = await slackAppSettingsChannelsUpdate(
                String(values.currentTeamId),
                String(integrationId),
                slackChannelId,
                change
            )
            if (integrationId !== values.selectedIntegrationId) {
                return
            }
            const others = (values.channels ?? []).filter((channel) => channel.slack_channel_id !== slackChannelId)
            actions.setChannels(hasChannelSetting(saved) ? [...others, saved] : others)
        }

        return {
            selectIntegration: () => actions.loadAll(),
            loadIntegrationsSuccess: () => actions.loadAll(),
            loadAll: () => {
                actions.loadSettings()
                actions.loadChannels()
            },
            openChannelModal: () => {
                if (values.repositoryOptions === null && !values.repositoryOptionsLoading) {
                    actions.loadRepositoryOptions()
                }
            },
            saveChannelDraft: async () => {
                const draft = values.channelDraft
                if (!draft?.slack_channel_id || values.selectedIntegrationId === null) {
                    return
                }
                actions.setChannelSaving(true)
                try {
                    await putChannel(draft.slack_channel_id, {
                        default_integration_id: draft.default_integration_id,
                        default_repository: draft.default_repository,
                        untagged_question_mode: draft.untagged_question_mode,
                    })
                    actions.closeChannelModal()
                } catch (error: any) {
                    lemonToast.error(error?.detail ?? "Couldn't save the channel settings. Try again.")
                } finally {
                    actions.setChannelSaving(false)
                }
            },
            removeChannel: async ({ slackChannelId }) => {
                if (values.selectedIntegrationId === null) {
                    return
                }
                try {
                    await putChannel(slackChannelId, {
                        default_integration_id: null,
                        default_repository: null,
                        untagged_question_mode: null,
                    })
                } catch (error: any) {
                    lemonToast.error(error?.detail ?? "Couldn't remove the channel settings. Try again.")
                }
            },
        }
    }),
    afterMount(({ actions, values }) => {
        if (values.slackIntegrations !== undefined) {
            actions.loadAll()
        }
    }),
])
