export interface ChannelDraft extends SlackAppChannelSettingsUpdateApi {
    slack_channel_id: string | null
}

const EMPTY_DRAFT: ChannelDraft = {
    slack_channel_id: null,
    default_integration_id: null,
    default_repository: null,
    untagged_question_mode: null,
}

export function hasChannelSetting(channel: SlackAppChannelSettingsUpdateApi): boolean {
    return (
        channel.default_integration_id !== null ||
        channel.default_repository !== null ||
        channel.untagged_question_mode !== null
    )
}

