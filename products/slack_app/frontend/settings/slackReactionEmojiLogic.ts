import { MakeLogicType, afterMount, connect, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { loadSlackStandardEmoji, SlackStandardEmoji } from 'lib/components/EmojiPicker/slackStandardEmoji'
import { teamLogic } from 'scenes/teamLogic'

import { slackAppSettingsEmojiRetrieve } from '../generated/api'
import type { SlackAppEmojiCatalogApi } from '../generated/api.schemas'

export interface SlackReactionEmojiLogicProps {
    integrationId: number
}

/** One emoji the picker offers. A custom emoji has an image, a standard one has a character. */
export interface PickerEmoji {
    name: string
    character: string | null
    imageUrl: string | null
    custom: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface slackReactionEmojiLogicValues {
    currentTeamId: number | null // teamLogic
    catalog: SlackAppEmojiCatalogApi | null
    catalogLoadFailed: boolean
    catalogLoading: boolean
    emojiByName: Record<string, PickerEmoji>
    pickerEmoji: PickerEmoji[]
    standardEmoji: SlackStandardEmoji[] | null
    standardEmojiLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface slackReactionEmojiLogicActions {
    loadCatalog: () => any
    loadCatalogFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadCatalogSuccess: (
        catalog: SlackAppEmojiCatalogApi,
        payload?: any
    ) => {
        catalog: SlackAppEmojiCatalogApi
        payload?: any
    }
    loadStandardEmoji: () => any
    loadStandardEmojiFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadStandardEmojiSuccess: (
        standardEmoji: SlackStandardEmoji[],
        payload?: any
    ) => {
        standardEmoji: SlackStandardEmoji[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface slackReactionEmojiLogicMeta {
    key: any
    __keaTypeGenInternalSelectorTypes: {
        emojiByName: (catalog: any, standardEmoji: any) => Record<string, PickerEmoji>
        pickerEmoji: (catalog: any, standardEmoji: any, emojiByName: any) => PickerEmoji[]
    }
}

export type slackReactionEmojiLogicType = MakeLogicType<
    slackReactionEmojiLogicValues,
    slackReactionEmojiLogicActions,
    SlackReactionEmojiLogicProps,
    slackReactionEmojiLogicMeta
>

export const slackReactionEmojiLogic = kea<slackReactionEmojiLogicType>([
    props({} as SlackReactionEmojiLogicProps),
    key((props) => props.integrationId),
    path((key) => ['products', 'slack_app', 'frontend', 'settings', 'slackReactionEmojiLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    loaders(({ props, values }) => ({
        catalog: [
            null as SlackAppEmojiCatalogApi | null,
            {
                loadCatalog: async () =>
                    await slackAppSettingsEmojiRetrieve(String(values.currentTeamId), String(props.integrationId)),
            },
        ],
        standardEmoji: [
            null as SlackStandardEmoji[] | null,
            {
                loadStandardEmoji: async () => await loadSlackStandardEmoji(),
            },
        ],
    })),
    reducers({
        catalogLoadFailed: [
            false,
            {
                loadCatalog: () => false,
                loadCatalogFailure: () => true,
            },
        ],
    }),
    selectors({
        emojiByName: [
            (s) => [s.catalog, s.standardEmoji],
            (
                catalog: SlackAppEmojiCatalogApi | null,
                standardEmoji: SlackStandardEmoji[] | null
            ): Record<string, PickerEmoji> => {
                const byName: Record<string, PickerEmoji> = {}
                for (const emoji of standardEmoji ?? []) {
                    for (const name of emoji.names) {
                        byName[name] = { name, character: emoji.character, imageUrl: null, custom: false }
                    }
                }
                for (const emoji of catalog?.custom_emoji ?? []) {
                    // An alias of a standard emoji has no image, so it shows that emoji's character.
                    const target = emoji.alias_for ? byName[emoji.alias_for] : undefined
                    byName[emoji.name] = {
                        name: emoji.name,
                        character: emoji.image_url ? null : (target?.character ?? null),
                        imageUrl: emoji.image_url,
                        custom: true,
                    }
                }
                return byName
            },
        ],
        // Custom emoji first, because a workspace that added its own usually wants one of them.
        pickerEmoji: [
            (s) => [s.catalog, s.standardEmoji, s.emojiByName],
            (
                catalog: SlackAppEmojiCatalogApi | null,
                standardEmoji: SlackStandardEmoji[] | null,
                emojiByName: Record<string, PickerEmoji>
            ): PickerEmoji[] => [
                ...(catalog?.custom_emoji ?? []).map((emoji) => emojiByName[emoji.name]),
                ...(standardEmoji ?? []).map((emoji) => emojiByName[emoji.name]),
            ],
        ],
    }),
    afterMount(({ actions, values }) => {
        if (values.catalog === null && !values.catalogLoading) {
            actions.loadCatalog()
        }
        if (values.standardEmoji === null && !values.standardEmojiLoading) {
            actions.loadStandardEmoji()
        }
    }),
])
