export type todayMonitorLogicType = MakeLogicType<
    todayMonitorLogicValues,
    todayMonitorLogicActions,
    Record<string, any>,
    todayMonitorLogicMeta
>

export const todayMonitorLogic = kea<todayMonitorLogicType>([
    path(['products', 'today', 'frontend', 'monitor', 'todayMonitorLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            router,
            ['location'],
            sidebarPinsLogic,
            ['shortcutData'],
            todayRecentsLogic,
            ['currentRecent', 'monitorRecentRows'],
        ],
    })),
    actions({
        toggleSection: (section: TodayMonitorSection) => ({ section }),
        setSearchQuery: (searchQuery: string) => ({ searchQuery }),
    }),
    reducers({
        searchQuery: ['', { setSearchQuery: (_, { searchQuery }) => searchQuery }],
        // pinned: storage key for the persisted sections. Renaming it reopens everyone's sections.
        collapsedSections: [
            [] as TodayMonitorSection[],
            TODAY_USER_PERSIST_OPTIONS,
            {
                toggleSection: (state, { section }) =>
                    state.includes(section) ? state.filter((id) => id !== section) : [...state, section],
            },
        ],
    }),
    selectors({
        products: [(s) => [s.featureFlags], (featureFlags: FeatureFlagsSet) => monitorItems(featureFlags)],
        matchingTools: [
            (s) => [s.products, s.searchQuery],
            (products: MonitorProducts, searchQuery: string): MonitorProduct[] =>
                products.tools.filter((product) => matchesPaneQuery(product.label, searchQuery)),
        ],
        matchingProducts: [
            (s) => [s.products, s.searchQuery],
            (products: MonitorProducts, searchQuery: string): MonitorProduct[] =>
                products.products.filter((product) => matchesPaneQuery(product.label, searchQuery)),
        ],
        pinnedRows: [
            (s) => [s.shortcutData],
            (shortcutData: FileSystemEntry[]): HrefPin<TodayMonitorRecentType>[] =>
                hrefPinsFromShortcuts(shortcutData, TODAY_MONITOR_RECENT_TYPES),
        ],
        matchingPinnedRows: [
            (s) => [s.pinnedRows, s.searchQuery],
            (pinnedRows: HrefPin<TodayMonitorRecentType>[], searchQuery: string): HrefPin<TodayMonitorRecentType>[] =>
                pinnedRows.filter((pin) => matchesPaneQuery(pin.name, searchQuery)),
        ],
        matchingRecentRows: [
            (s) => [s.monitorRecentRows, s.pinnedRows, s.searchQuery],
            (
                monitorRecentRows: TodayMonitorRecent[],
                pinnedRows: HrefPin<TodayMonitorRecentType>[],
                searchQuery: string
            ): TodayMonitorRecent[] =>
                unpinnedRecents(monitorRecentRows, pinnedRows).filter((recent) =>
                    matchesPaneQuery(recent.name, searchQuery)
                ),
        ],
        activeRow: [
            (s) => [s.location, s.currentRecent, s.pinnedRows, s.monitorRecentRows],
            (
                location: { pathname: string },
                currentRecent: TodayRecent | null,
                pinnedRows: HrefPin<TodayMonitorRecentType>[],
                monitorRecentRows: TodayMonitorRecent[]
            ): string | null =>
                activeMonitorRow(location.pathname, currentRecent, [...pinnedRows, ...monitorRecentRows]),
        ],
        isSearching: [(s) => [s.searchQuery], (searchQuery: string): boolean => searchQuery.trim() !== ''],
        /** A search opens every section, so no match hides in a collapsed one. */
        isSectionOpen: [
            (s) => [s.collapsedSections, s.isSearching],
            (collapsedSections: TodayMonitorSection[], isSearching: boolean) =>
                (section: TodayMonitorSection): boolean =>
                    isSearching || !collapsedSections.includes(section),
        ],
    }),
    listeners(({ values }) => ({
        toggleSection: ({ section }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('monitor section toggled', {
                section,
                open: !values.collapsedSections.includes(section),
            })
        },
    })),
])
