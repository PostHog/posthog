import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'

import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { removeProjectIdIfPresent } from 'lib/utils/kea-router'

import { TodayPaneProduct } from '~/layout/today/todayPaneProducts'
import { matchesPaneQuery } from '~/layout/today/todayPaneSearch'

import { HomeProducts, homeItems, homeProductForPath } from './todayHomeRows'

export function activeHomeRow(pathname: string): string | null {
    const product = homeProductForPath(removeProjectIdIfPresent(pathname))
    return product ? `product:${product.key}` : null
}

function matchingProducts(products: TodayPaneProduct[], searchQuery: string): TodayPaneProduct[] {
    return products.filter((product) => matchesPaneQuery(product.label, searchQuery))
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayHomeLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    location: {
        pathname: string
        search: string
        hash: string
    } // router
    activeRow: string | null
    matching: HomeProducts
    noMatches: boolean
    products: HomeProducts
    searchQuery: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayHomeLogicActions {
    setSearchQuery: (searchQuery: string) => {
        searchQuery: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayHomeLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        products: (featureFlags: FeatureFlagsSet) => HomeProducts
        matching: (products: HomeProducts, searchQuery: string) => HomeProducts
        noMatches: (searchQuery: string, matching: HomeProducts) => boolean
        activeRow: (location: { hash: string; pathname: string; search: string }) => string | null
    }
}

export type todayHomeLogicType = MakeLogicType<
    todayHomeLogicValues,
    todayHomeLogicActions,
    Record<string, any>,
    todayHomeLogicMeta
>

export const todayHomeLogic = kea<todayHomeLogicType>([
    path(['products', 'today', 'frontend', 'home', 'todayHomeLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], router, ['location']],
    })),
    actions({
        setSearchQuery: (searchQuery: string) => ({ searchQuery }),
    }),
    reducers({
        searchQuery: ['', { setSearchQuery: (_, { searchQuery }) => searchQuery }],
    }),
    selectors({
        products: [(s) => [s.featureFlags], (featureFlags: FeatureFlagsSet): HomeProducts => homeItems(featureFlags)],
        matching: [
            (s) => [s.products, s.searchQuery],
            (products: HomeProducts, searchQuery: string): HomeProducts => ({
                top: matchingProducts(products.top, searchQuery),
                bottom: matchingProducts(products.bottom, searchQuery),
            }),
        ],
        noMatches: [
            (s) => [s.searchQuery, s.matching],
            (searchQuery: string, matching: HomeProducts): boolean =>
                searchQuery.trim() !== '' && matching.top.length === 0 && matching.bottom.length === 0,
        ],
        activeRow: [
            (s) => [s.location],
            (location: { pathname: string }): string | null => activeHomeRow(location.pathname),
        ],
    }),
])
