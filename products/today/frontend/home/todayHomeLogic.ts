export function activeHomeRow(pathname: string): string | null {
    const product = homeProductForPath(removeProjectIdIfPresent(pathname))
    return product ? `product:${product.key}` : null
}

function matchingProducts(products: TodayPaneProduct[], searchQuery: string): TodayPaneProduct[] {
    return products.filter((product) => matchesPaneQuery(product.label, searchQuery))
}

export type TodayHomeSection = 'pinned' | 'recents'

interface HomeRecentsPage {
    entries: FileSystemEntry[]
    hasNext: boolean
}

/**
 * The project's most recently viewed records. The recents endpoint honours `limit` but not `offset`, so showing more
 * asks again for a longer list. It sets neither a total nor a `next` link, so a full list is the only sign of more.
 */
async function loadRecentsPage(limit: number): Promise<HomeRecentsPage> {
    const response = await api.fileSystem.list({ orderBy: '-last_viewed_at', notType: 'folder', limit })
    return { entries: response.results, hasNext: response.results.length === limit }
}

