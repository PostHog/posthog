export type todaySeasonalChecklistLogicType = MakeLogicType<
    todaySeasonalChecklistLogicValues,
    todaySeasonalChecklistLogicActions,
    TodaySeasonalChecklistLogicProps,
    todaySeasonalChecklistLogicMeta
>

function captureChecklistEvent(
    event: string,
    { checklist }: TodaySeasonalChecklistLogicProps,
    values: Pick<todaySeasonalChecklistLogicValues, 'flagVariant' | 'doneCount' | 'items'>,
    properties: Record<string, unknown> = {}
): void {
    posthog.capture(event, {
        campaign: checklist.campaign,
        flag_variant: values.flagVariant,
        done_count: values.doneCount,
        item_count: values.items.length,
        ...properties,
    })
}

export const todaySeasonalChecklistLogic: LogicWrapper<todaySeasonalChecklistLogicType> =
    kea<todaySeasonalChecklistLogicType>([
        props({} as TodaySeasonalChecklistLogicProps),
        key(({ checklist }) => checklist.campaign),
        path((campaign) => ['products', 'today', 'seasonal', 'todaySeasonalChecklistLogic', campaign]),
        connect(() => ({
            values: [featureFlagLogic, ['featureFlags']],
        })),
        actions({
            openChecklist: true,
            closeChecklist: true,
            setItemDone: (key: string, done: boolean, source: SeasonalItemSource) => ({ key, done, source }),
            itemActionClicked: (key: string) => ({ key }),
            dismissChecklist: true,
            restoreChecklist: true,
        }),
        reducers({
            isOpen: [
                false,
                {
                    openChecklist: () => true,
                    closeChecklist: () => false,
                    itemActionClicked: () => false,
                    dismissChecklist: () => false,
                },
            ],
            completedKeys: [
                [] as string[],
                { persist: true },
                {
                    setItemDone: (state, { key, done }) =>
                        done ? (state.includes(key) ? state : [...state, key]) : state.filter((k) => k !== key),
                },
            ],
            dismissed: [
                false,
                { persist: true },
                {
                    dismissChecklist: () => true,
                    restoreChecklist: () => false,
                },
            ],
        }),
        selectors({
            items: [() => [(_, props) => props.checklist], (checklist: SeasonalChecklist) => checklist.items],
            doneKeys: [
                (s) => [s.items, s.completedKeys],
                (items: SeasonalChecklistItem[], completedKeys: string[]): Set<string> =>
                    new Set(items.map((item) => item.key).filter((k) => completedKeys.includes(k))),
            ],
            doneCount: [(s) => [s.doneKeys], (doneKeys: Set<string>): number => doneKeys.size],
            allDone: [
                (s) => [s.items, s.doneCount],
                (items: SeasonalChecklistItem[], doneCount: number): boolean => doneCount === items.length,
            ],
            nextItemKey: [
                (s) => [s.items, s.doneKeys],
                (items: SeasonalChecklistItem[], doneKeys: Set<string>): string | null =>
                    items.find((item) => !doneKeys.has(item.key))?.key ?? null,
            ],
            flagVariant: [
                (s) => [s.featureFlags],
                (featureFlags: FeatureFlagsSet): string | boolean | null =>
                    peekFeatureFlag(featureFlags, FEATURE_FLAGS.TODAY_SEASONAL_CHECKLIST) ?? null,
            ],
        }),
        listeners(({ actions, values, props }) => {
            const capture = (event: string, properties?: Record<string, unknown>): void =>
                captureChecklistEvent(event, props, values, properties)
            return {
                openChecklist: () => capture(EVENTS.opened),
                setItemDone: ({ key, done, source }) => {
                    if (!done) {
                        return
                    }
                    capture(EVENTS.itemCompleted, { item_key: key, source })
                    if (values.allDone) {
                        capture(EVENTS.completed)
                    }
                },
                itemActionClicked: ({ key }) => {
                    if (!values.doneKeys.has(key)) {
                        actions.setItemDone(key, true, 'action')
                    }
                },
                dismissChecklist: () => {
                    capture(EVENTS.dismissed)
                    toast({
                        title: 'Checklist hidden',
                        action: { label: 'Undo', onClick: () => actions.restoreChecklist() },
                    })
                },
                restoreChecklist: () => capture(EVENTS.restored),
            }
        }),
        afterMount(({ values, props }) => {
            if (!values.dismissed) {
                captureChecklistEvent(EVENTS.shown, props, values)
            }
        }),
    ])
