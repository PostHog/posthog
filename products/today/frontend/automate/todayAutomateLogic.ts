export const todayAutomateLogic = kea<todayAutomateLogicType>([
    path(['products', 'today', 'frontend', 'automate', 'todayAutomateLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            router,
            ['location'],
            sidebarPinsLogic,
            ['shortcutData'],
            todayRecentsLogic,
            ['currentRecent', 'automateRecentRows'],
        ],
    })),
    actions({
        toggleSection: (section: TodayAutomateSection) => ({ section }),
        setSearchQuery: (searchQuery: string) => ({ searchQuery }),
    }),
    reducers({
        searchQuery: ['', { setSearchQuery: (_, { searchQuery }) => searchQuery }],
        // pinned: storage key for the persisted sections. Renaming it reopens everyone's sections.
        collapsedSections: [
            [] as TodayAutomateSection[],
            TODAY_USER_PERSIST_OPTIONS,
            {
                toggleSection: (state, { section }) =>
                    state.includes(section) ? state.filter((id) => id !== section) : [...state, section],
            },
        ],
    }),
    selectors({
        products: [(s) => [s.featureFlags], (featureFlags: FeatureFlagsSet) => automateItems(featureFlags)],
        matching: [
            (s) => [s.products, s.searchQuery],
            (products: TodayPaneProduct[], searchQuery: string): TodayPaneProduct[] =>
                matchingProducts(products, searchQuery),
        ],
        pinnedRows: [
            (s) => [s.shortcutData],
            (shortcutData: FileSystemEntry[]): HrefPin<TodayAutomateRecentType>[] =>
                hrefPinsFromShortcuts(shortcutData, TODAY_AUTOMATE_RECENT_TYPES),
        ],
        matchingPinnedRows: [
            (s) => [s.pinnedRows, s.searchQuery],
            (pinnedRows: HrefPin<TodayAutomateRecentType>[], searchQuery: string): HrefPin<TodayAutomateRecentType>[] =>
                pinnedRows.filter((pin) => matchesPaneQuery(pin.name, searchQuery)),
        ],
        matchingRecentRows: [
            (s) => [s.automateRecentRows, s.pinnedRows, s.searchQuery],
            (
                automateRecentRows: TodayAutomateRecent[],
                pinnedRows: HrefPin<TodayAutomateRecentType>[],
                searchQuery: string
            ): TodayAutomateRecent[] =>
                unpinnedRecents(automateRecentRows, pinnedRows).filter((recent) =>
                    matchesPaneQuery(recent.name, searchQuery)
                ),
        ],
        activeRow: [
            (s) => [s.location, s.currentRecent, s.pinnedRows, s.automateRecentRows],
            (
                location: { pathname: string },
                currentRecent: TodayRecent | null,
                pinnedRows: HrefPin<TodayAutomateRecentType>[],
                automateRecentRows: TodayAutomateRecent[]
            ): string | null =>
                activeAutomateRow(location.pathname, currentRecent, [...pinnedRows, ...automateRecentRows]),
        ],
        isSearching: [(s) => [s.searchQuery], (searchQuery: string): boolean => searchQuery.trim() !== ''],
        noMatches: [
            (s) => [s.isSearching, s.matching, s.matchingPinnedRows, s.matchingRecentRows],
            (
                isSearching: boolean,
                matching: TodayPaneProduct[],
                matchingPinnedRows: HrefPin<TodayAutomateRecentType>[],
                matchingRecentRows: TodayAutomateRecent[]
            ): boolean =>
                isSearching &&
                matching.length === 0 &&
                matchingPinnedRows.length === 0 &&
                matchingRecentRows.length === 0,
        ],
        /** A search opens every section, so no match hides in a collapsed one. */
        isSectionOpen: [
            (s) => [s.collapsedSections, s.isSearching],
            (collapsedSections: TodayAutomateSection[], isSearching: boolean) =>
                (section: TodayAutomateSection): boolean =>
                    isSearching || !collapsedSections.includes(section),
        ],
    }),
    listeners(({ values }) => ({
        toggleSection: ({ section }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('automate section toggled', {
                section,
                open: !values.collapsedSections.includes(section),
            })
        },
    })),
])
