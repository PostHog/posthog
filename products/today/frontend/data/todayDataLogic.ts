// pinned: persisted section ids and the `section` property of `data section toggled`.
export type TodayDataSection = 'pinned' | 'recents' | 'warehouse' | 'definitions' | 'setup'

export function activeDataRow(
    pathname: string,
    currentRecent: TodayRecent | null,
    rows: Pick<TodayDataRecent, 'href'>[]
): string | null {
    if (currentRecent && rows.some((row) => row.href === currentRecent.href)) {
        return recentRowKey(currentRecent.href)
    }
    const product = dataProductForPath(removeProjectIdIfPresent(pathname))
    return product ? `product:${product.key}` : null
}

function matchingProducts(products: TodayPaneProduct[], searchQuery: string): TodayPaneProduct[] {
    return products.filter((product) => matchesPaneQuery(product.label, searchQuery))
}

