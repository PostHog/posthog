export type todayDataLogicType = MakeLogicType<
    todayDataLogicValues,
    todayDataLogicActions,
    Record<string, any>,
    todayDataLogicMeta
>

export const todayDataLogic = kea<todayDataLogicType>([
    path(['products', 'today', 'frontend', 'data', 'todayDataLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            router,
            ['location'],
            sidebarPinsLogic,
            ['shortcutData'],
            todayRecentsLogic,
            ['currentRecent', 'dataRecentRows'],
        ],
    })),
    actions({
        toggleSection: (section: TodayDataSection) => ({ section }),
        setSearchQuery: (searchQuery: string) => ({ searchQuery }),
    }),
    reducers({
        searchQuery: ['', { setSearchQuery: (_, { searchQuery }) => searchQuery }],
        // pinned: storage key for the persisted sections. Renaming it reopens everyone's sections.
        collapsedSections: [
            [] as TodayDataSection[],
            TODAY_USER_PERSIST_OPTIONS,
            {
                toggleSection: (state, { section }) =>
                    state.includes(section) ? state.filter((id) => id !== section) : [...state, section],
            },
        ],
    }),
    selectors({
        products: [(s) => [s.featureFlags], (featureFlags: FeatureFlagsSet) => dataItems(featureFlags)],
        matching: [
            (s) => [s.products, s.searchQuery],
            (products: DataProducts, searchQuery: string): DataProducts => ({
                pipeline: matchingProducts(products.pipeline, searchQuery),
                warehouse: matchingProducts(products.warehouse, searchQuery),
                definitions: matchingProducts(products.definitions, searchQuery),
                setup: matchingProducts(products.setup, searchQuery),
            }),
        ],
        pinnedRows: [
            (s) => [s.shortcutData],
            (shortcutData: FileSystemEntry[]): HrefPin<TodayDataRecentType>[] =>
                hrefPinsFromShortcuts(shortcutData, TODAY_DATA_RECENT_TYPES),
        ],
        matchingPinnedRows: [
            (s) => [s.pinnedRows, s.searchQuery],
            (pinnedRows: HrefPin<TodayDataRecentType>[], searchQuery: string): HrefPin<TodayDataRecentType>[] =>
                pinnedRows.filter((pin) => matchesPaneQuery(pin.name, searchQuery)),
        ],
        matchingRecentRows: [
            (s) => [s.dataRecentRows, s.pinnedRows, s.searchQuery],
            (
                dataRecentRows: TodayDataRecent[],
                pinnedRows: HrefPin<TodayDataRecentType>[],
                searchQuery: string
            ): TodayDataRecent[] =>
                unpinnedRecents(dataRecentRows, pinnedRows).filter((recent) =>
                    matchesPaneQuery(recent.name, searchQuery)
                ),
        ],
        activeRow: [
            (s) => [s.location, s.currentRecent, s.pinnedRows, s.dataRecentRows],
            (
                location: { pathname: string },
                currentRecent: TodayRecent | null,
                pinnedRows: HrefPin<TodayDataRecentType>[],
                dataRecentRows: TodayDataRecent[]
            ): string | null => activeDataRow(location.pathname, currentRecent, [...pinnedRows, ...dataRecentRows]),
        ],
        isSearching: [(s) => [s.searchQuery], (searchQuery: string): boolean => searchQuery.trim() !== ''],
        noMatches: [
            (s) => [s.isSearching, s.matching, s.matchingPinnedRows, s.matchingRecentRows],
            (
                isSearching: boolean,
                matching: DataProducts,
                matchingPinnedRows: HrefPin<TodayDataRecentType>[],
                matchingRecentRows: TodayDataRecent[]
            ): boolean =>
                isSearching &&
                Object.values(matching).every((products) => products.length === 0) &&
                matchingPinnedRows.length === 0 &&
                matchingRecentRows.length === 0,
        ],
        /** A search opens every section, so no match hides in a collapsed one. */
        isSectionOpen: [
            (s) => [s.collapsedSections, s.isSearching],
            (collapsedSections: TodayDataSection[], isSearching: boolean) =>
                (section: TodayDataSection): boolean =>
                    isSearching || !collapsedSections.includes(section),
        ],
    }),
    listeners(({ values }) => ({
        toggleSection: ({ section }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('data section toggled', {
                section,
                open: !values.collapsedSections.includes(section),
            })
        },
    })),
])
