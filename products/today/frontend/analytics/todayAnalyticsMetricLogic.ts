export const todayAnalyticsMetricLogic = kea<todayAnalyticsMetricLogicType>([
    props({} as TodayAnalyticsMetricLogicProps),
    key((props) => props.shortId),
    path((key) => ['layout', 'today', 'todayAnalyticsMetricLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentProjectId']] })),
    actions({ setRefreshedInsight: (insight: InsightApi) => ({ insight }) }),
    loaders(({ props, values }) => ({
        insight: [
            null as InsightApi | null,
            {
                // A sidebar must not start a blocking query on page load. An unfinished background refresh is
                // observed below so its completed result can update this row.
                loadInsight: async () => {
                    const { results } = await insightsList(String(values.currentProjectId), {
                        short_id: props.shortId,
                        refresh: 'async',
                    })
                    return results[0] ?? null
                },
            },
        ],
    })),
    reducers({
        loadFailed: [false, { loadInsight: () => false, loadInsightFailure: () => true }],
        refreshedInsight: [
            null as InsightApi | null,
            { loadInsight: () => null, setRefreshedInsight: (_, { insight }) => insight },
        ],
    }),
    selectors({
        metric: [
            (s) => [s.insight, s.refreshedInsight],
            (insight: InsightApi | null, refreshedInsight: InsightApi | null) => {
                const shown = refreshedInsight ?? insight
                return shown ? metricFromInsight(shown) : null
            },
        ],
    }),
    listeners(({ actions, cache, props, values }) => ({
        loadInsight: () => cache.disposables.dispose('refreshPoll'),
        loadInsightSuccess: ({ insight }) => {
            cache.disposables.dispose('refreshPoll')
            const status = (insight?.query_status ?? null) as QueryStatusApi | null
            if (!status?.id || status.complete || status.error) {
                return
            }
            const projectId = String(values.currentProjectId)
            cache.disposables.add(
                () => {
                    const controller = new AbortController()
                    void (async () => {
                        try {
                            const { pollForResults, isExpiredQueryStatusError } = await retryImport(
                                () => import('~/queries/query')
                            )
                            if (controller.signal.aborted) {
                                return
                            }
                            try {
                                const completed = await pollForResults(status.id, { signal: controller.signal })
                                if (completed.error) {
                                    return
                                }
                            } catch (error) {
                                if (!isExpiredQueryStatusError(error)) {
                                    throw error
                                }
                            }
                            if (controller.signal.aborted) {
                                return
                            }
                            const { results } = await insightsList(
                                projectId,
                                { short_id: props.shortId, refresh: 'force_cache' },
                                { signal: controller.signal }
                            )
                            const refreshedStatus = (results[0]?.query_status ?? null) as QueryStatusApi | null
                            if (!controller.signal.aborted && results[0]?.result != null && !refreshedStatus?.error) {
                                actions.setRefreshedInsight(results[0])
                            }
                        } catch {
                            // The linked row keeps its cached value when a background refresh fails.
                        }
                    })()
                    return () => controller.abort()
                },
                'refreshPoll',
                { pauseOnPageHidden: false }
            )
        },
    })),
    afterMount(({ actions }) => {
        actions.loadInsight()
    }),
])
