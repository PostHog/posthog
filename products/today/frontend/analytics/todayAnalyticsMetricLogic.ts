import { loaders } from 'kea-loaders'

import {
    METRIC_SUMMARY_DEFAULT,
    computeMetricSummary,
    computeMetricSummaryChange,
    selectCurrentSeries,
} from 'lib/components/Metric/metricSummary'
import { retryImport } from 'lib/utils/retryImport'
import { teamLogic } from 'scenes/teamLogic'

import { TrendsFilter } from '~/queries/schema/schema-general'
import { TrendResult } from '~/types'

import { insightsList } from 'products/product_analytics/frontend/generated/api'
import type { InsightApi, QueryStatusApi } from 'products/product_analytics/frontend/generated/api.schemas'

export interface TodayAnalyticsMetricLogicProps {
    shortId: string
}

export interface TodayAnalyticsMetricValue {
    value: number
    change: ReturnType<typeof computeMetricSummaryChange>
    data: number[]
    labels: string[]
    trendsFilter: TrendsFilter | null
}

function querySource(insight: InsightApi): { kind?: string; trendsFilter?: TrendsFilter } | undefined {
    return (insight.query as { source?: { kind?: string; trendsFilter?: TrendsFilter } } | null)?.source
}

export function isTrendsInsight(insight: InsightApi): boolean {
    return querySource(insight)?.kind === 'TrendsQuery'
}

/** The number a trends insight shows, as its Metric display sums it up. Null for any other insight, or before its first result. */
export function metricFromInsight(insight: InsightApi): TodayAnalyticsMetricValue | null {
    const source = querySource(insight)
    const results = Array.isArray(insight.result) ? (insight.result as TrendResult[]) : undefined
    const series = selectCurrentSeries(results)
    if (!isTrendsInsight(insight) || !series || (series.count == null && series.aggregated_value == null)) {
        return null
    }
    const trendsFilter = source?.trendsFilter ?? null
    const summary = trendsFilter?.metricSummary ?? METRIC_SUMMARY_DEFAULT
    const current = { total: series.aggregated_value ?? series.count, data: series.data ?? [] }
    const previousSeries = results?.find((result) => result.compare_label === 'previous')
    const previous = previousSeries
        ? { total: previousSeries.aggregated_value ?? previousSeries.count, data: previousSeries.data ?? [] }
        : undefined
    return {
        value: computeMetricSummary(summary, current.total, current.data),
        change: computeMetricSummaryChange(summary, current, previous),
        data: current.data,
        labels: series.labels ?? [],
        trendsFilter,
    }
}

