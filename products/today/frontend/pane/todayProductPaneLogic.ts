// pinned: part of the storage key of each pane's persisted sections, kept from the logic each pane had before.
// Changing one reopens everyone's sections in that pane.
const PANE_LOGIC_PATHS: Record<TodayProductPaneKey, string[]> = {
    monitor: ['products', 'today', 'frontend', 'monitor', 'todayMonitorLogic'],
    automate: ['products', 'today', 'frontend', 'automate', 'todayAutomateLogic'],
    data: ['products', 'today', 'frontend', 'data', 'todayDataLogic'],
}

export const todayProductPaneLogic = kea<todayProductPaneLogicType>([
    props({} as TodayProductPaneLogicProps),
    key((props) => props.pane),
    path((pane) => PANE_LOGIC_PATHS[pane as TodayProductPaneKey]),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            router,
            ['location'],
            sidebarPinsLogic,
            ['shortcutData'],
            todayRecentsLogic,
            ['currentRecent', 'productPaneRecents'],
        ],
    })),
    actions({
        toggleSection: (section: string) => ({ section }),
        setSearchQuery: (searchQuery: string) => ({ searchQuery }),
    }),
    loaders(({ props, values }) => ({
        recentHistory: [
            [] as TodayRecent[],
            {
                loadRecentHistory: async () => {
                    try {
                        return (await productPaneConfig(props.pane).loadRecentHistory?.()) ?? []
                    } catch {
                        // Recents are a side list, so a failed load keeps the current list instead of showing an error toast.
                        return values.recentHistory
                    }
                },
            },
        ],
    })),
    reducers({
        searchQuery: ['', { setSearchQuery: (_, { searchQuery }) => searchQuery }],
        collapsedSections: [
            [] as string[],
            TODAY_USER_PERSIST_OPTIONS,
            {
                toggleSection: (state, { section }) =>
                    state.includes(section) ? state.filter((id) => id !== section) : [...state, section],
            },
        ],
    }),
    selectors({
        config: [() => [(_, props) => props.pane], (pane: TodayProductPaneKey) => productPaneConfig(pane)],
        products: [
            (s) => [s.config, s.featureFlags],
            (config: TodayProductPaneConfig, featureFlags: FeatureFlagsSet): TodayPaneProducts =>
                filterPaneProducts(paneProducts(config), (product) => isPaneProductShown(product, featureFlags)),
        ],
        matching: [
            (s) => [s.products, s.searchQuery],
            (products: TodayPaneProducts, searchQuery: string): TodayPaneProducts =>
                filterPaneProducts(products, (product) => matchesPaneQuery(product.label, searchQuery)),
        ],
        pinnedRows: [
            (s) => [s.config, s.shortcutData],
            (config: TodayProductPaneConfig, shortcutData: FileSystemEntry[]): HrefPin<string>[] =>
                hrefPinsFromShortcuts(shortcutData, config.recentTypes),
        ],
        matchingPinnedRows: [
            (s) => [s.pinnedRows, s.searchQuery],
            (pinnedRows: HrefPin<string>[], searchQuery: string): HrefPin<string>[] =>
                pinnedRows.filter((pin) => matchesPaneQuery(pin.name, searchQuery)),
        ],
        recentRows: [
            (s, p) => [s.productPaneRecents, s.recentHistory, p.pane],
            (
                productPaneRecents: Record<TodayProductPaneKey, TodayRecent[]>,
                recentHistory: TodayRecent[],
                pane: TodayProductPaneKey
            ): TodayRecent[] => paneRecentRows(productPaneRecents[pane], recentHistory),
        ],
        matchingRecentRows: [
            (s) => [s.recentRows, s.pinnedRows, s.searchQuery],
            (recentRows: TodayRecent[], pinnedRows: HrefPin<string>[], searchQuery: string): TodayRecent[] =>
                unpinnedRecents(recentRows, pinnedRows).filter((recent) => matchesPaneQuery(recent.name, searchQuery)),
        ],
        activeRow: [
            (s) => [s.config, s.location, s.currentRecent, s.pinnedRows, s.recentRows],
            (
                config: TodayProductPaneConfig,
                location: { pathname: string },
                currentRecent: TodayRecent | null,
                pinnedRows: HrefPin<string>[],
                recentRows: TodayRecent[]
            ): string | null => activePaneRow(config, location.pathname, currentRecent, [...pinnedRows, ...recentRows]),
        ],
        isSearching: [(s) => [s.searchQuery], (searchQuery: string): boolean => searchQuery.trim() !== ''],
        noMatches: [
            (s) => [s.isSearching, s.matching, s.matchingPinnedRows, s.matchingRecentRows],
            (
                isSearching: boolean,
                matching: TodayPaneProducts,
                matchingPinnedRows: HrefPin<string>[],
                matchingRecentRows: TodayRecent[]
            ): boolean =>
                isSearching &&
                matching.lead.length === 0 &&
                matching.sections.every(({ products }) => products.length === 0) &&
                matchingPinnedRows.length === 0 &&
                matchingRecentRows.length === 0,
        ],
        /** A search opens every section, so no match hides in a collapsed one. */
        isSectionOpen: [
            (s) => [s.collapsedSections, s.isSearching],
            (collapsedSections: string[], isSearching: boolean) =>
                (section: string): boolean =>
                    isSearching || !collapsedSections.includes(section),
        ],
    }),
    listeners(({ props, values }) => ({
        toggleSection: ({ section }) => {
            // pinned: analytics event name, such as `monitor section toggled`, and its properties. Renaming them
            // breaks dashboards.
            posthog.capture(`${props.pane} section toggled`, {
                section,
                open: !values.collapsedSections.includes(section),
            })
        },
    })),
    afterMount(({ actions, props }) => {
        if (productPaneConfig(props.pane).loadRecentHistory) {
            actions.loadRecentHistory()
        }
    }),
])
