/**
 * The pane's Recents: the records opened under this pane first, then the ones from the server's view history. Both
 * lists arrive newest first, so the limit keeps the newest records before the rows sort by name.
 */
export function paneRecentRows(recents: TodayRecent[], history: TodayRecent[]): TodayRecent[] {
    const hrefs = new Set(recents.map((recent) => recent.href))
    return newestByName(
        [...recents, ...history.filter((recent) => !hrefs.has(recent.href))],
        (recent) => recent.name,
        (recent) => recent.href,
        TODAY_RECENTS_LIMIT
    )
}

export function activePaneRow(
    config: TodayProductPaneConfig,
    pathname: string,
    currentRecent: TodayRecent | null,
    rows: Pick<TodayRecent, 'href'>[]
): string | null {
    if (currentRecent && rows.some((row) => row.href === currentRecent.href)) {
        return recentRowKey(currentRecent.href)
    }
    const product = paneConfigProductForPath(config, removeProjectIdIfPresent(pathname))
    return product ? `product:${product.key}` : null
}

