import { LogicWrapper, MakeLogicType, afterMount, kea, key, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiConfig, ApiError } from 'lib/api'

import { apiErrorDetail } from './checksApi'
import * as api from './generated/api'
import type { DataQualityCheckScheduleApi, PatchedDataQualityCheckScheduleUpdateApi } from './generated/api.schemas'

export interface DataQualityScheduleLogicProps {
    metricId: string
}

export interface DataQualityScheduleError {
    message: string
    uncertain: boolean
}

const REJECTED_SCHEDULE_MESSAGE = 'Could not save the schedule. Try again.'

function isDefinitiveRejection(error: unknown): boolean {
    return error instanceof ApiError && error.status !== undefined && error.status < 500
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataQualityScheduleLogicValues {
    schedule: DataQualityCheckScheduleApi | null
    scheduleError: DataQualityScheduleError | null
    scheduleLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataQualityScheduleLogicActions {
    loadSchedule: () => any
    loadScheduleFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadScheduleSuccess: (
        schedule: DataQualityCheckScheduleApi,
        payload?: any
    ) => {
        schedule: DataQualityCheckScheduleApi
        payload?: any
    }
    updateSchedule: (patch: PatchedDataQualityCheckScheduleUpdateApi) => PatchedDataQualityCheckScheduleUpdateApi
    updateScheduleFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    updateScheduleSuccess: (
        schedule: DataQualityCheckScheduleApi,
        payload?: PatchedDataQualityCheckScheduleUpdateApi
    ) => {
        schedule: DataQualityCheckScheduleApi
        payload?: PatchedDataQualityCheckScheduleUpdateApi
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataQualityScheduleLogicMeta {
    key: string
}

export type dataQualityScheduleLogicType = MakeLogicType<
    dataQualityScheduleLogicValues,
    dataQualityScheduleLogicActions,
    DataQualityScheduleLogicProps,
    dataQualityScheduleLogicMeta
>

export const dataQualityScheduleLogic: LogicWrapper<dataQualityScheduleLogicType> = kea<dataQualityScheduleLogicType>([
    props({} as DataQualityScheduleLogicProps),
    key((props) => props.metricId),
    path((key) => ['products', 'data_quality', 'frontend', 'dataQualityScheduleLogic', key]),
    loaders(({ props, actions }) => ({
        schedule: [
            null as DataQualityCheckScheduleApi | null,
            {
                loadSchedule: async () =>
                    api.dataCatalogMetricsChecksScheduleRetrieve(String(ApiConfig.getCurrentTeamId()), props.metricId),
                updateSchedule: async (patch: PatchedDataQualityCheckScheduleUpdateApi) => {
                    try {
                        return await api.dataCatalogMetricsChecksSchedulePartialUpdate(
                            String(ApiConfig.getCurrentTeamId()),
                            props.metricId,
                            patch
                        )
                    } catch (error) {
                        if (isDefinitiveRejection(error)) {
                            throw error
                        }
                        try {
                            actions.loadScheduleSuccess(
                                await api.dataCatalogMetricsChecksScheduleRetrieve(
                                    String(ApiConfig.getCurrentTeamId()),
                                    props.metricId
                                )
                            )
                        } catch {
                            // The edit can have committed even when neither response reaches us.
                        }
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        scheduleError: [
            null as DataQualityScheduleError | null,
            {
                loadSchedule: () => null,
                updateSchedule: () => null,
                loadScheduleFailure: (_, { error }) => ({ message: error, uncertain: true }),
                updateScheduleFailure: (_, { error, errorObject }) => ({
                    message: apiErrorDetail(errorObject) ?? error ?? REJECTED_SCHEDULE_MESSAGE,
                    uncertain: !isDefinitiveRejection(errorObject),
                }),
            },
        ],
    }),
    afterMount(({ actions }) => actions.loadSchedule()),
])
