import { LogicWrapper, MakeLogicType, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { subscriptions } from 'kea-subscriptions'

import { teamLogic } from 'scenes/teamLogic'
import { pagePerformanceLogic } from 'scenes/web-analytics/pagePerformanceLogic'
import { WebAnalyticsLogicProps } from 'scenes/web-analytics/webAnalyticsLogicProps'

import { WebAnalyticsPropertyFilters } from '~/queries/schema/schema-general'

import { runCancellableRequest } from 'products/web_analytics/frontend/pageReports/cancellableRequest'

import type { TeamPublicType, TeamType } from '../../../../frontend/src/types'
import { AiAssistantRow } from './AiAssistantList'
import { PagePerformanceWindow, loadAiAssistantRows } from './searchAndAiQueries'

