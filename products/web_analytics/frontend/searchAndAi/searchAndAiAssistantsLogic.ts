export type searchAndAiAssistantsLogicType = MakeLogicType<
    searchAndAiAssistantsLogicValues,
    searchAndAiAssistantsLogicActions,
    WebAnalyticsLogicProps,
    searchAndAiAssistantsLogicMeta
>

export const searchAndAiAssistantsLogic: LogicWrapper<searchAndAiAssistantsLogicType> =
    kea<searchAndAiAssistantsLogicType>([
        props({} as WebAnalyticsLogicProps),
        key((props) => props.context ?? 'web-analytics'),
        path((key) => ['products', 'webAnalytics', 'searchAndAi', 'searchAndAiAssistantsLogic', key]),
        connect((props: WebAnalyticsLogicProps) => ({
            values: [
                pagePerformanceLogic(props),
                ['window', 'pathExpr', 'filterTestAccounts', 'webAnalyticsFilters'],
                teamLogic,
                ['currentTeam'],
            ],
            actions: [pagePerformanceLogic(props), ['reloadAll']],
        })),
        loaders(({ values, cache }) => ({
            assistants: [
                null as AiAssistantRow[] | null,
                {
                    loadAssistants: async ({ refresh }: { refresh?: boolean }, breakpoint) => {
                        await breakpoint(300)
                        return await runCancellableRequest(
                            cache.disposables,
                            'assistants',
                            () => values.currentTeam?.id ?? null,
                            breakpoint,
                            (request) =>
                                loadAiAssistantRows(
                                    {
                                        window: values.window,
                                        page: null,
                                        pathExpr: values.pathExpr,
                                        filterTestAccounts: values.filterTestAccounts,
                                        properties: values.webAnalyticsFilters,
                                    },
                                    { ...request, refresh: refresh ? 'force_blocking' : 'blocking' }
                                )
                        )
                    },
                },
            ],
        })),
        reducers({
            assistantsFailed: [
                false,
                {
                    loadAssistants: () => false,
                    loadAssistantsFailure: () => true,
                },
            ],
        }),
        selectors({
            assistantsInput: [
                (s) => [s.window, s.filterTestAccounts, s.webAnalyticsFilters],
                (
                    window: PagePerformanceWindow,
                    filterTestAccounts: boolean,
                    webAnalyticsFilters: WebAnalyticsPropertyFilters
                ): string => JSON.stringify([window, filterTestAccounts, webAnalyticsFilters]),
            ],
        }),
        listeners(({ actions }) => ({
            reloadAll: () => actions.loadAssistants({ refresh: true }),
        })),
        subscriptions(({ actions }) => ({
            assistantsInput: () => actions.loadAssistants({}),
        })),
    ])
