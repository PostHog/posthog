function filterKey(filters: CommonFilters, width: number): string {
    return JSON.stringify({
        date_from: filters.date_from || '-7d',
        date_to: filters.date_to || null,
        cohort_ids: [...(filters.cohort_ids ?? [])].sort((a, b) => a - b),
        events: selectedEventFilters(filters.events),
        filter_test_accounts: filters.filter_test_accounts ?? false,
        width,
    })
}

