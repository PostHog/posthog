export const historicalHeatmapLogic = kea<historicalHeatmapLogicType>([
    props({} as HistoricalHeatmapProps),
    key((props) => props.heatmapId),
    path((key) => ['products', 'web_analytics', 'historicalHeatmapLogic', key]),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeam', 'currentTeamIdStrict'],
            heatmapDataLogic({ context: 'in-app' }),
            ['commonFilters', 'widthOverride'],
        ],
    })),
    actions({
        startAnalysis: true,
        loadAnalysis: (id: string) => ({ id }),
        changeRepresentative: (variantId: string, momentId: string) => ({ variantId, momentId }),
        selectVariant: (variantId: string | null) => ({ variantId }),
        navigateVariant: (direction: -1 | 1) => ({ direction }),
        showMore: true,
        setAppliedFilterKey: (key: string) => ({ key }),
    }),
    loaders(({ props, values, actions }) => ({
        result: [
            null as HeatmapAnalysisResultApi | null,
            {
                loadAnalysis: async ({ id }, breakpoint) => {
                    const result = await heatmapAnalysesRetrieve(String(values.currentTeamIdStrict), id)
                    breakpoint()
                    if (result.analysis.heatmap_id !== props.heatmapId) {
                        throw new Error('This analysis belongs to another heatmap.')
                    }
                    if (values.result?.analysis.id !== result.analysis.id) {
                        const timezone = values.timezone
                        const shared = heatmapDataLogic({ context: 'in-app' })
                        const from = dayjs(result.analysis.date_from).tz(timezone)
                        const to = dayjs(result.analysis.date_to).tz(timezone)
                        shared.actions.setCommonFilters({
                            date_from: from.format(
                                from.isSame(from.startOf('day')) ? 'YYYY-MM-DD' : 'YYYY-MM-DD HH:mm:ss'
                            ),
                            date_to: to.isSame(to.startOf('day'))
                                ? to.subtract(1, 'day').format('YYYY-MM-DD')
                                : to.format('YYYY-MM-DD HH:mm:ss'),
                            cohort_ids: result.analysis.filters.cohort_ids,
                            events: result.analysis.filters.events as CommonFilters['events'],
                            filter_test_accounts: result.analysis.filters.filter_test_accounts,
                        })
                        shared.actions.setWindowWidthOverride(result.analysis.viewport_width)
                        actions.setAppliedFilterKey(
                            filterKey(shared.values.commonFilters, result.analysis.viewport_width)
                        )
                    }
                    return result
                },
                startAnalysis: async (_, breakpoint) => {
                    const submittedFilterKey = values.currentFilterKey
                    const timezone = values.timezone
                    const from = dateStringToDayJs(values.commonFilters.date_from || '-7d', timezone)
                    const rawTo = values.commonFilters.date_to
                    const to =
                        rawTo && /^\d{4}-\d{2}-\d{2}$/.test(rawTo)
                            ? dateStringToDayJs(dayjs(rawTo).add(1, 'day').format('YYYY-MM-DD'), timezone)
                            : rawTo
                              ? dateStringToDayJs(rawTo, timezone)
                              : dayjs()
                    if (!from || !to) {
                        throw new Error('Choose a date range of up to 90 days.')
                    }
                    const analysis = await heatmapAnalysesCreate(String(values.currentTeamIdStrict), {
                        heatmap_id: props.heatmapId,
                        date_from: from.toISOString(),
                        date_to: to.toISOString(),
                        viewport_width: values.widthOverride,
                        filter_test_accounts: values.commonFilters.filter_test_accounts ?? false,
                        cohort_ids: JSON.stringify(values.commonFilters.cohort_ids ?? []),
                        events: eventFilterParam(values.commonFilters.events),
                    })
                    breakpoint()
                    router.actions.replace(router.values.location.pathname, {
                        ...router.values.searchParams,
                        historical_analysis: analysis.id,
                    })
                    const result = await heatmapAnalysesRetrieve(String(values.currentTeamIdStrict), analysis.id)
                    breakpoint()
                    actions.setAppliedFilterKey(submittedFilterKey)
                    return result
                },
                changeRepresentative: async ({ variantId, momentId }, breakpoint) => {
                    if (!values.result) {
                        return null
                    }
                    const result = await heatmapAnalysesRepresentativeCreate(
                        String(values.currentTeamIdStrict),
                        values.result.analysis.id,
                        { variant_id: variantId, moment_id: momentId }
                    )
                    breakpoint()
                    return result
                },
            },
        ],
    })),
    reducers(() => ({
        selectedVariantId: [
            null as string | null,
            {
                selectVariant: (_, { variantId }) => variantId,
                startAnalysisSuccess: () => null,
            },
        ],
        appliedFilterKey: [null as string | null, { setAppliedFilterKey: (_, { key }) => key }],
        error: [
            null as string | null,
            {
                startAnalysis: () => null,
                loadAnalysis: () => null,
                loadAnalysisFailure: (_, { error }) => error,
                startAnalysisFailure: (_, { error }) => error,
                changeRepresentativeFailure: (_, { error }) => error,
            },
        ],
        visibleCount: [6, { showMore: (count) => count + 6, startAnalysis: () => 6 }],
    })),
    selectors({
        timezone: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): string => currentTeam?.timezone ?? 'UTC',
        ],
        currentFilterKey: [
            (s) => [s.commonFilters, s.widthOverride],
            (filters: CommonFilters, width: number): string => filterKey(filters, width),
        ],
        filtersChanged: [
            (s) => [s.appliedFilterKey, s.currentFilterKey],
            (applied: string | null, current: string): boolean => applied !== null && applied !== current,
        ],
        sortedVariants: [
            (s) => [s.result],
            (result: HeatmapAnalysisResultApi | null): HeatmapAnalysisVariantApi[] =>
                [...(result?.variants ?? [])].sort((a, b) => a.first_seen - b.first_seen || a.id.localeCompare(b.id)),
        ],
        selectedVariantIndex: [
            (s) => [s.sortedVariants, s.selectedVariantId],
            (variants: HeatmapAnalysisVariantApi[], id: string | null): number =>
                variants.findIndex((variant) => variant.id === id),
        ],
        selectedVariant: [
            (s) => [s.sortedVariants, s.selectedVariantIndex],
            (variants: HeatmapAnalysisVariantApi[], index: number): HeatmapAnalysisVariantApi | null =>
                variants[index] ?? null,
        ],
        processing: [
            (s) => [s.result],
            (result: HeatmapAnalysisResultApi | null): boolean =>
                ['queued', 'processing'].includes(result?.analysis.status ?? ''),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const syncPolling = (): void => {
            const id = values.result?.analysis.id
            if (!id || !values.processing) {
                cache.disposables.dispose('poll')
                return
            }
            cache.disposables.add(() => {
                const timer = window.setInterval(() => {
                    if (!values.resultLoading) {
                        actions.loadAnalysis(id)
                    }
                }, 3000)
                return () => window.clearInterval(timer)
            }, 'poll')
        }
        return {
            navigateVariant: ({ direction }) => {
                const variant = values.sortedVariants[values.selectedVariantIndex + direction]
                if (values.selectedVariantIndex >= 0 && variant) {
                    actions.selectVariant(variant.id)
                }
            },
            startAnalysis: () => cache.disposables.dispose('poll'),
            loadAnalysisFailure: syncPolling,
            loadAnalysisSuccess: syncPolling,
            startAnalysisSuccess: syncPolling,
        }
    }),
    urlToAction(({ actions, values }) => ({
        '*': (_, searchParams) => {
            const id = searchParams.historical_analysis
            if (typeof id === 'string' && id !== values.result?.analysis.id && !values.resultLoading) {
                actions.loadAnalysis(id)
            }
        },
    })),
])
