const CAPTURES_PER_PAGE = 4

export function isUsableCapture(capture: HeatmapScreenshotHistoryItemApi): boolean {
    return capture.status === 'ok' && !!capture.content_url
}
function isExpiredCapture(capture: HeatmapScreenshotHistoryItemApi): boolean {
    return dayjs(capture.expires_at).isBefore(dayjs())
}
function sortCapturesOldestFirst(captures: HeatmapScreenshotHistoryItemApi[]): HeatmapScreenshotHistoryItemApi[] {
    return [...captures].sort((a, b) => a.captured_on.localeCompare(b.captured_on))
}
export function selectCapturesBetween(
    captures: HeatmapScreenshotHistoryItemApi[],
    anchorId: string | null,
    extentId: string | null
): HeatmapScreenshotHistoryItemApi[] {
    const anchor = captures.find((capture) => capture.id === anchorId)
    if (!anchor || !isUsableCapture(anchor)) {
        return []
    }
    const extent = extentId ? captures.find((capture) => capture.id === extentId) : anchor
    if (!extent || !isUsableCapture(extent)) {
        return []
    }
    const [from, to] = [anchor.captured_on, extent.captured_on].sort()
    const selected = sortCapturesOldestFirst(
        captures.filter(
            (capture) => isUsableCapture(capture) && capture.captured_on >= from && capture.captured_on <= to
        )
    )
    return selected.every((capture) => capture.width === anchor.width && capture.timezone === anchor.timezone)
        ? selected
        : []
}

