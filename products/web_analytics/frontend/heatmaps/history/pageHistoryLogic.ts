export const pageHistoryLogic = kea<pageHistoryLogicType>([
    path((key) => ['products', 'web_analytics', 'heatmaps', 'history', 'pageHistoryLogic', key]),
    props({} as PageHistoryLogicProps),
    key((props) => `${props.teamId ?? teamLogic.values.currentTeamIdStrict}:${props.id}`),
    connect((props: PageHistoryLogicProps) => ({
        values: [
            heatmapLogic({ id: props.id }),
            ['savedSettings', 'hasUnsavedChanges'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [
            heatmapLogic({ id: props.id }),
            ['setSavedSettings', 'setPageUrlDraft', 'setType', 'setDataUrl'],
            heatmapDataLogic({ context: 'in-app' }),
            ['setHistoryView'],
            featureFlagLogic,
            ['setFeatureFlags'],
        ],
    })),
    actions({
        pageChanged: true,
        selectCapture: (id: string) => ({ id }),
        browseCapture: (id: string) => ({ id }),
        navigateCapture: (direction: 'previous' | 'next') => ({ direction }),
        setMissingCaptureDate: (date: string | null) => ({ date }),
        setNavigationNotice: (notice: string | null) => ({ notice }),
        openRangeEditor: true,
        setRangeEditorOpen: (open: boolean) => ({ open }),
        setRangeDraft: (fromId: string, toId: string) => ({ fromId, toId }),
        applyRangeDraft: true,
        setSelectionRange: (anchorId: string, extentId: string) => ({ anchorId, extentId }),
        setHistoryPage: (page: number) => ({ page }),
        setHistoryExpanded: (expanded: boolean) => ({ expanded }),
        clearSelection: true,
        applySelection: true,
    }),
    loaders(({ props, cache }) => ({
        history: [
            null as HeatmapScreenshotHistoryResponseApi | null,
            {
                loadHistory: async (_: void, breakpoint) => {
                    const history = await savedScreenshotHistoryRetrieve(String(cache.teamId), props.id)
                    breakpoint()
                    return history
                },
            },
        ],
    })),
    reducers({
        anchorId: [
            null as string | null,
            {
                selectCapture: (_, { id }) => id,
                setSelectionRange: (_, { anchorId }) => anchorId,
                clearSelection: () => null,
            },
        ],
        extentId: [
            null as string | null,
            {
                selectCapture: (_, { id }) => id,
                setSelectionRange: (_, { extentId }) => extentId,
                clearSelection: () => null,
            },
        ],
        historyExpanded: [
            false,
            {
                setHistoryExpanded: (_, { expanded }) => expanded,
                clearSelection: () => false,
                openRangeEditor: () => false,
            },
        ],
        rangeEditorOpen: [
            false,
            {
                setRangeEditorOpen: (_, { open }) => open,
                openRangeEditor: () => true,
                clearSelection: () => false,
                selectCapture: () => false,
            },
        ],
        rangeDraft: [
            null as { fromId: string; toId: string } | null,
            { setRangeDraft: (_, { fromId, toId }) => ({ fromId, toId }) },
        ],
        missingCaptureDate: [
            null as string | null,
            { setMissingCaptureDate: (_, { date }) => date, selectCapture: () => null, clearSelection: () => null },
        ],
        navigationNotice: [
            null as string | null,
            { setNavigationNotice: (_, { notice }) => notice, selectCapture: () => null, clearSelection: () => null },
        ],
        history: { pageChanged: () => null },
        historyPage: [0, { setHistoryPage: (_, { page }) => Math.max(0, page), pageChanged: () => 0 }],
        historyLoadFailed: [false, { loadHistory: () => false, loadHistoryFailure: () => true }],
    }),
    selectors({
        pageHistoryEnabled: [
            (s) => [s.featureFlags],
            (flags: FeatureFlagsSet): boolean => !!flags[FEATURE_FLAGS.HEATMAPS_PAGE_HISTORY],
        ],
        captures: [
            (s) => [s.history],
            (history: HeatmapScreenshotHistoryResponseApi | null): HeatmapScreenshotHistoryItemApi[] =>
                sortCapturesOldestFirst(history?.results ?? []),
        ],
        historyPageCount: [
            (s) => [s.captures],
            (captures: HeatmapScreenshotHistoryItemApi[]): number =>
                Math.max(1, Math.ceil(captures.length / CAPTURES_PER_PAGE)),
        ],
        visibleCaptures: [
            (s) => [s.captures, s.historyPage, s.historyPageCount],
            (
                captures: HeatmapScreenshotHistoryItemApi[],
                page: number,
                count: number
            ): HeatmapScreenshotHistoryItemApi[] => {
                const end = captures.length - Math.min(page, count - 1) * CAPTURES_PER_PAGE
                return captures.slice(Math.max(0, end - CAPTURES_PER_PAGE), end)
            },
        ],
        usableCaptures: [
            (s) => [s.captures],
            (captures: HeatmapScreenshotHistoryItemApi[]): HeatmapScreenshotHistoryItemApi[] =>
                captures.filter(isUsableCapture),
        ],
        previousCapture: [
            (s) => [s.usableCaptures, s.selectedBackground],
            (
                captures: HeatmapScreenshotHistoryItemApi[],
                background: HeatmapScreenshotHistoryItemApi | null
            ): HeatmapScreenshotHistoryItemApi | null =>
                background
                    ? (captures[captures.findIndex((capture) => capture.id === background.id) - 1] ?? null)
                    : null,
        ],
        nextCapture: [
            (s) => [s.usableCaptures, s.selectedBackground],
            (
                captures: HeatmapScreenshotHistoryItemApi[],
                background: HeatmapScreenshotHistoryItemApi | null
            ): HeatmapScreenshotHistoryItemApi | null =>
                background
                    ? (captures[captures.findIndex((capture) => capture.id === background.id) + 1] ?? null)
                    : null,
        ],
        missingDateAlternatives: [
            (s) => [s.usableCaptures, s.missingCaptureDate],
            (captures: HeatmapScreenshotHistoryItemApi[], date: string | null): HeatmapScreenshotHistoryItemApi[] => {
                if (!date) {
                    return []
                }
                return [
                    captures.filter((capture) => capture.captured_on < date).at(-1),
                    captures.find((capture) => capture.captured_on > date),
                ].filter((capture): capture is HeatmapScreenshotHistoryItemApi => !!capture)
            },
        ],
        rangeDraftError: [
            (s) => [s.captures, s.rangeDraft, s.historyBrowseDisabledReason],
            (
                captures: HeatmapScreenshotHistoryItemApi[],
                draft: { fromId: string; toId: string } | null,
                disabledReason: string | null
            ): string | null => {
                if (disabledReason) {
                    return disabledReason
                }
                const from = captures.find((capture) => capture.id === draft?.fromId)
                const to = captures.find((capture) => capture.id === draft?.toId)
                if (!from || !to || !isUsableCapture(from) || !isUsableCapture(to)) {
                    return 'Choose available screenshots for both dates.'
                }
                if (from.captured_on > to.captured_on) {
                    return 'Choose a start date on or before the end date.'
                }
                if (!selectCapturesBetween(captures, from.id, to.id).some((capture) => capture.id === to.id)) {
                    return 'Combined days need screenshots with the same screen width and timezone.'
                }
                return null
            },
        ],
        rangeDraftCaptures: [
            (s) => [s.captures, s.rangeDraft, s.rangeDraftError],
            (
                captures: HeatmapScreenshotHistoryItemApi[],
                draft: { fromId: string; toId: string } | null,
                error: string | null
            ): HeatmapScreenshotHistoryItemApi[] =>
                draft && !error ? selectCapturesBetween(captures, draft.fromId, draft.toId) : [],
        ],
        rangeDraftBackground: [
            (s) => [s.rangeDraftCaptures],
            (captures: HeatmapScreenshotHistoryItemApi[]): HeatmapScreenshotHistoryItemApi | null =>
                captures.at(-1) ?? null,
        ],
        historyBrowseDisabledReason: [
            (s) => [s.hasUnsavedChanges],
            (hasUnsavedChanges: boolean): string | null =>
                hasUnsavedChanges ? 'Save or discard your page changes to explore history.' : null,
        ],
        selectedCaptures: [
            (s) => [s.captures, s.anchorId, s.extentId],
            (
                captures: HeatmapScreenshotHistoryItemApi[],
                anchorId: string | null,
                extentId: string | null
            ): HeatmapScreenshotHistoryItemApi[] => selectCapturesBetween(captures, anchorId, extentId),
        ],
        selectedDateRange: [
            (s) => [s.selectedCaptures],
            (captures: HeatmapScreenshotHistoryItemApi[]): HeatmapDateRangeOverride | null =>
                captures.length
                    ? {
                          date_from: captures[0].captured_on,
                          date_to: captures[captures.length - 1].captured_on,
                          timestamp_from: captures[0].day_start,
                          timestamp_to: captures[captures.length - 1].day_end,
                      }
                    : null,
        ],
        selectedBackground: [
            (s) => [s.selectedCaptures],
            (captures: HeatmapScreenshotHistoryItemApi[]): HeatmapScreenshotHistoryItemApi | null =>
                captures[captures.length - 1] ?? null,
        ],
        isSelectionActive: [
            (s) => [s.selectedCaptures],
            (captures: HeatmapScreenshotHistoryItemApi[]): boolean => captures.length > 0,
        ],
        isCombinedRange: [
            (s) => [s.selectedDateRange],
            (range: HeatmapDateRangeOverride | null): boolean => !!range && range.date_from !== range.date_to,
        ],
    }),
    listeners(({ actions, values, cache, key, props }) => {
        const clearSelectionOnUnsavedChange = (): void => {
            if (values.hasUnsavedChanges && values.isSelectionActive) {
                actions.clearSelection()
            }
        }
        const restoreCurrentView = (): void => {
            actions.clearSelection()
            actions.setNavigationNotice(
                'A selected screenshot is no longer available. Your current view has been restored. Choose another date to continue.'
            )
            actions.setHistoryExpanded(true)
        }
        return {
            setSavedSettings: ({ settings }) => {
                const urlKey = JSON.stringify([settings.url, settings.data_url])
                if (cache.urlKey && cache.urlKey !== urlKey) {
                    actions.pageChanged()
                }
                cache.urlKey = urlKey
            },
            pageChanged: () => {
                actions.clearSelection()
                if (values.pageHistoryEnabled && props.id !== 'new') {
                    actions.loadHistory()
                }
            },
            setFeatureFlags: () => {
                if (values.pageHistoryEnabled && props.id !== 'new' && !values.history && !values.historyLoading) {
                    actions.loadHistory()
                }
            },
            setPageUrlDraft: clearSelectionOnUnsavedChange,
            setDataUrl: clearSelectionOnUnsavedChange,
            setType: ({ type }) => {
                if (type !== 'screenshot' && values.isSelectionActive) {
                    actions.clearSelection()
                }
            },
            browseCapture: ({ id }) => {
                if (values.historyBrowseDisabledReason) {
                    return
                }
                const capture = values.captures.find((capture) => capture.id === id)
                if (!capture) {
                    return
                }
                if (!isUsableCapture(capture)) {
                    actions.setMissingCaptureDate(capture.captured_on)
                    return
                }
                actions.selectCapture(id)
            },
            navigateCapture: ({ direction }) => {
                const from = values.selectedBackground
                const to = direction === 'previous' ? values.previousCapture : values.nextCapture
                if (!from || !to || values.historyBrowseDisabledReason) {
                    return
                }
                actions.selectCapture(to.id)
                const missingDays = Math.abs(dayjs(to.captured_on).diff(dayjs(from.captured_on), 'day')) - 1
                if (missingDays > 0) {
                    actions.setNavigationNotice(
                        `Moved to ${formatCaptureDay(to.captured_on)}. Skipped ${missingDays} ${missingDays === 1 ? 'day' : 'days'} with no saved screenshot.`
                    )
                }
            },
            openRangeEditor: () => {
                const selected = values.selectedCaptures
                const latest = values.usableCaptures.at(-1)
                if (!latest) {
                    actions.setRangeEditorOpen(false)
                    return
                }
                actions.setRangeDraft(selected[0]?.id ?? latest.id, selected.at(-1)?.id ?? latest.id)
            },
            applyRangeDraft: () => {
                const draft = values.rangeDraft
                if (!draft || values.rangeDraftError) {
                    return
                }
                actions.setSelectionRange(draft.fromId, draft.toId)
                actions.setRangeEditorOpen(false)
                actions.setMissingCaptureDate(null)
                actions.setNavigationNotice(null)
            },
            selectCapture: ({ id }) => {
                const index = values.captures.findIndex((capture) => capture.id === id)
                if (index >= 0) {
                    actions.setHistoryPage(Math.floor((values.captures.length - index - 1) / CAPTURES_PER_PAGE))
                }
                actions.applySelection()
            },
            setSelectionRange: () => actions.applySelection(),
            applySelection: () => {
                const background = values.selectedBackground
                const range = values.selectedDateRange
                if (!background?.content_url || !range) {
                    actions.clearSelection()
                    return
                }
                if (values.selectedCaptures.some(isExpiredCapture)) {
                    restoreCurrentView()
                    actions.loadHistory()
                    return
                }
                const view: HeatmapHistoryView = {
                    owner: key,
                    dateRange: range,
                    width: background.width,
                    imageUrl: background.content_url,
                }
                if (!objectsEqual(heatmapDataLogic({ context: 'in-app' }).values.historyView, view)) {
                    actions.setHistoryView(view)
                }
            },
            clearSelection: () => {
                const data = heatmapDataLogic({ context: 'in-app' })
                if (data.values.historyView?.owner === key) {
                    actions.setHistoryView(null)
                }
            },
            loadHistorySuccess: () => {
                actions.setHistoryPage(Math.min(values.historyPage, values.historyPageCount - 1))
                if (values.anchorId) {
                    if (heatmapDataLogic({ context: 'in-app' }).values.historyView?.owner !== key) {
                        actions.clearSelection()
                    } else if (values.selectedCaptures.length > 0) {
                        actions.applySelection()
                    } else {
                        restoreCurrentView()
                    }
                }
            },
        }
    }),
    afterMount(({ actions, props, values, cache }) => {
        cache.teamId = props.teamId ?? teamLogic.values.currentTeamIdStrict
        if (values.savedSettings) {
            cache.urlKey = JSON.stringify([values.savedSettings.url, values.savedSettings.data_url])
        }
        if (values.pageHistoryEnabled && props.id !== 'new') {
            actions.loadHistory()
        }
    }),
    beforeUnmount(({ key }) => {
        const data = heatmapDataLogic({ context: 'in-app' })
        if (data.values.historyView?.owner === key) {
            data.actions.setHistoryView(null)
        }
    }),
])
