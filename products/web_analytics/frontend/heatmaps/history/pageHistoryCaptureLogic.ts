export const pageHistoryCaptureLogic = kea<pageHistoryCaptureLogicType>([
    path((key) => ['products', 'web_analytics', 'heatmaps', 'history', 'pageHistoryCaptureLogic', key]),
    props({} as PageHistoryLogicProps),
    key((props) => `${props.teamId ?? teamLogic.values.currentTeamIdStrict}:${props.id}`),
    connect((props: PageHistoryLogicProps) => ({
        values: [
            pageHistoryLogic(props),
            ['captures', 'history'],
            heatmapLogic({ id: props.id }),
            ['editDisabledReason', 'hasUnsavedChanges'],
            teamLogic,
            ['timezone'],
        ],
        actions: [pageHistoryLogic(props), ['loadHistory', 'loadHistorySuccess', 'pageChanged']],
    })),
    actions({
        requestCapture: true,
        captureNow: true,
        setCapturing: (capturing: boolean) => ({ capturing }),
        setCaptureError: (error: string | null) => ({ error }),
        setCaptureStatusUnknown: (unknown: boolean) => ({ unknown }),
        setCompletedRequestId: (requestId: string | null) => ({ requestId }),
        pollRequest: (requestId: string) => ({ requestId }),
        stopPolling: true,
    }),
    reducers({
        captureError: [
            null as string | null,
            {
                setCaptureError: (_, { error }) => error,
                setCapturing: (state, { capturing }) => (capturing ? null : state),
            },
        ],
        captureStatusUnknown: [false, { setCaptureStatusUnknown: (_, { unknown }) => unknown }],
        completedRequestId: [
            null as string | null,
            {
                setCompletedRequestId: (_, { requestId }) => requestId,
                setCapturing: (state, { capturing }) => (capturing ? null : state),
            },
        ],
        capturing: [false, { setCapturing: (_, { capturing }) => capturing, stopPolling: () => false }],
    }),
    selectors({
        completedCapture: [
            (s) => [s.captures, s.completedRequestId],
            (
                captures: HeatmapScreenshotHistoryItemApi[],
                requestId: string | null
            ): HeatmapScreenshotHistoryItemApi | null =>
                requestId
                    ? (captures.find((capture) => capture.revision === requestId && isUsableCapture(capture)) ?? null)
                    : null,
        ],
        todaysCapture: [
            (s) => [s.captures, s.timezone],
            (captures: HeatmapScreenshotHistoryItemApi[], timezone: string): HeatmapScreenshotHistoryItemApi | null => {
                const today = dayjs().tz(timezone).format('YYYY-MM-DD')
                return captures.find((capture) => capture.captured_on === today && isUsableCapture(capture)) ?? null
            },
        ],
        captureNowDisabledReason: [
            (s) => [s.editDisabledReason, s.capturing, s.history, s.hasUnsavedChanges, s.captureStatusUnknown],
            (
                editDisabledReason: string | null,
                capturing: boolean,
                history: HeatmapScreenshotHistoryResponseApi | null,
                hasUnsavedChanges: boolean,
                captureStatusUnknown: boolean
            ): string | null =>
                editDisabledReason ||
                (hasUnsavedChanges
                    ? 'Save your page settings before capturing.'
                    : captureStatusUnknown
                      ? 'Check the current capture before starting another.'
                      : !history
                        ? 'Load page history before capturing.'
                        : history.storage_available === false
                          ? 'Screenshot storage is unavailable on this installation.'
                          : capturing
                            ? 'Capturing the page'
                            : null),
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        pageChanged: () => {
            actions.stopPolling()
            actions.setCaptureError(null)
            actions.setCompletedRequestId(null)
        },
        loadHistorySuccess: ({ history }) => {
            const pending = history?.results
                .map((capture) => capture.latest_request)
                .find((request) => request && ['queued', 'running'].includes(request.state))
            actions.setCaptureStatusUnknown(false)
            if (pending && !values.capturing) {
                actions.pollRequest(pending.request_id)
            }
        },
        requestCapture: () => {
            if (values.captureNowDisabledReason) {
                return
            }
            if (values.todaysCapture) {
                LemonDialog.open({
                    title: "Replace today's capture?",
                    description:
                        "Only one screenshot is kept per day. A successful update replaces today's image; earlier interactions today may not match the new layout. Your previous screenshot stays available if the update fails.",
                    primaryButton: { children: 'Replace capture', onClick: () => actions.captureNow() },
                    secondaryButton: { children: 'Keep existing capture' },
                })
            } else {
                actions.captureNow()
            }
        },
        stopPolling: () => cache.disposables.dispose('history-poll'),
        pollRequest: ({ requestId }) => {
            actions.setCaptureStatusUnknown(false)
            actions.setCapturing(true)
            const giveUpAt = Date.now() + 30 * 60_000
            cache.disposables.add(() => {
                let cancelled = false
                let timer: ReturnType<typeof setTimeout> | undefined
                const poll = async (): Promise<void> => {
                    try {
                        const request = await savedScreenshotHistoryRequestsRetrieve(
                            String(cache.teamId),
                            props.id,
                            requestId
                        )
                        if (cancelled) {
                            return
                        }
                        if (['succeeded', 'failed', 'cancelled'].includes(request.state)) {
                            actions.stopPolling()
                            actions.loadHistory()
                            if (request.state === 'succeeded') {
                                actions.setCompletedRequestId(requestId)
                            } else {
                                actions.setCaptureError(
                                    request.state === 'cancelled'
                                        ? 'The capture was canceled. Existing screenshots are kept.'
                                        : "The capture couldn't finish. Existing screenshots are kept. Try again later."
                                )
                            }
                            return
                        }
                        if (Date.now() >= giveUpAt) {
                            throw new Error('Capture did not finish')
                        }
                        timer = setTimeout(poll, 10_000)
                    } catch {
                        if (!cancelled) {
                            actions.stopPolling()
                            actions.setCaptureStatusUnknown(true)
                        }
                    }
                }
                timer = setTimeout(poll, 10_000)
                return () => {
                    cancelled = true
                    clearTimeout(timer)
                }
            }, 'history-poll')
        },
        captureNow: async (_, breakpoint) => {
            if (values.captureNowDisabledReason) {
                return
            }
            actions.setCapturing(true)
            try {
                const request = await savedScreenshotHistoryCaptureCreate(String(cache.teamId), props.id)
                breakpoint()
                if (cache.disposables.isDisposed) {
                    return
                }
                actions.pollRequest(request.request_id)
                actions.loadHistory()
                posthog.capture('heatmap page history capture requested', { heatmap_id: props.id })
            } catch (error) {
                if (!cache.disposables.isDisposed) {
                    actions.setCapturing(false)
                    actions.setCaptureError(
                        error instanceof ApiError && error.status === 429
                            ? `A capture was requested recently. Try again in ${Math.max(1, Math.ceil(Number(error.headers?.get('Retry-After') ?? 600) / 60))} minutes.`
                            : 'Could not start a capture. Try again later.'
                    )
                }
            }
        },
    })),
    afterMount(({ props, cache }) => {
        cache.teamId = props.teamId ?? teamLogic.values.currentTeamIdStrict
    }),
])
