const QUERY_TAGS = { scene: 'Heatmaps', productKey: 'heatmaps' } as const

const urlPredicate = (href: string, matchType: 'exact' | 'pattern'): string =>
    matchType === 'pattern'
        ? hogql`match(current_url, ${heatmapUrlPatternToRegex(href)})`
        : hogql`trimRight(current_url, '/') = trimRight(${href}, '/')`

const pageOf = (url: string): string | null => {
    try {
        const parsed = new URL(url)
        return `${parsed.origin}${parsed.pathname.replace(/\/+$/, '')}`
    } catch {
        return null
    }
}

