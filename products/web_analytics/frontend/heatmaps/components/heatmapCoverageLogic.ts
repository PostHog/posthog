export const heatmapCoverageLogic = kea<heatmapCoverageLogicType>([
    path(['products', 'web_analytics', 'frontend', 'heatmaps', 'components', 'heatmapCoverageLogic']),
    connect(() => ({
        values: [
            heatmapDataLogic({ context: 'in-app' }),
            ['href', 'hrefMatchType', 'commonFilters', 'heatmapFilters', 'analysisWidth', 'heatmapEmpty'],
            heatmapsBrowserLogic,
            ['hasValidReplayIframeData', 'recordingUrlMatchMode', 'replayIframeData', 'dataUrl'],
            teamLogic,
            ['currentTeam'],
        ],
        actions: [
            heatmapDataLogic({ context: 'in-app' }),
            ['loadHeatmapSuccess', 'setWindowWidthOverride', 'patchHeatmapFilters'],
            heatmapsBrowserLogic,
            ['setRecordingUrlMatchMode', 'setReplayIframeDataURL', 'setDataUrl'],
        ],
    })),
    actions({
        applySuggestion: (url?: string) => ({ url }),
        reportEmptyDiagnosis: true,
    }),
    loaders(({ values }) => ({
        coverage: [
            null as { key: string; rows: HeatmapCoverageRow[] } | null,
            {
                loadCoverage: async (_, breakpoint) => {
                    const { href, hrefMatchType, commonFilters, coverageKey } = values
                    if (!href?.trim() || !coverageKey) {
                        return null
                    }
                    if (values.coverage?.key === coverageKey) {
                        return values.coverage
                    }
                    await breakpoint(300)
                    const query = hogql`
                        SELECT type, toInt(viewport_width * scale_factor) AS width, count() AS count
                        FROM heatmaps
                        WHERE ${hogql.raw(urlPredicate(href, hrefMatchType))} AND {filters(timestamp AS timestamp)}
                        GROUP BY type, width
                        ORDER BY count DESC
                        LIMIT 2000`
                    const response = await api.queryHogQL(query, QUERY_TAGS, {
                        queryParams: {
                            filters: {
                                dateRange: {
                                    date_from: commonFilters.date_from ?? '-7d',
                                    date_to: commonFilters.date_to ?? null,
                                },
                            },
                        },
                    })
                    breakpoint()
                    return {
                        key: coverageKey,
                        rows: (response.results ?? []).map(([type, width, count]: [HeatmapKind, number, number]) => ({
                            type,
                            width,
                            count,
                        })),
                    }
                },
            },
        ],
        urlDiagnosis: [
            null as (HeatmapUrlDiagnosis & { key: string }) | null,
            {
                loadUrlDiagnosis: async (_, breakpoint) => {
                    const { href, hrefMatchType, sourceUrl, urlDiagnosisKey } = values
                    if (!href?.trim() || !sourceUrl || !urlDiagnosisKey) {
                        return null
                    }
                    if (values.urlDiagnosis?.key === urlDiagnosisKey) {
                        return values.urlDiagnosis
                    }
                    await breakpoint(300)
                    const page = heatmapPageUrl(sourceUrl)
                    const pageCondition = page
                        ? hogql`trimRight(cutQueryStringAndFragment(current_url), '/') = ${page}`
                        : hogql`0`
                    const sameUrl = urlPredicate(href, hrefMatchType)
                    const inScope = hogql`timestamp >= now() - INTERVAL 90 DAY AND ${hogql.raw(relatedUrlPredicate(sourceUrl, page))}`
                    const totalsQuery = hogql`
                        SELECT countIf(${hogql.raw(sameUrl)}), countIf(${hogql.raw(pageCondition)})
                        FROM heatmaps
                        WHERE ${hogql.raw(inScope)}`
                    const similarUrlsQuery = hogql`
                        SELECT current_url, count() AS count
                        FROM heatmaps
                        WHERE ${hogql.raw(inScope)} AND NOT (${hogql.raw(sameUrl)}) AND NOT (${hogql.raw(pageCondition)})
                        GROUP BY current_url
                        ORDER BY count DESC
                        LIMIT 5`
                    const [totals, similar] = await Promise.all([
                        api.queryHogQL(totalsQuery, QUERY_TAGS),
                        api.queryHogQL(similarUrlsQuery, QUERY_TAGS),
                    ])
                    breakpoint()
                    const [sameUrlAnyDateCount, pageAnyQueryCount]: [number, number] = totals.results?.[0] ?? [0, 0]
                    return {
                        key: urlDiagnosisKey,
                        sameUrlAnyDateCount,
                        pageAnyQueryCount,
                        similarUrls: (similar.results ?? []).map(([url, count]: [string, number]) => ({ url, count })),
                    }
                },
            },
        ],
    })),
    selectors({
        sourceUrl: [
            (s) => [s.hasValidReplayIframeData, s.replayIframeData, s.dataUrl],
            (
                hasValidReplayIframeData: boolean,
                replayIframeData: ReplayIframeData | null,
                dataUrl: string | null
            ): string | null => (hasValidReplayIframeData ? replayIframeData?.url : dataUrl) ?? null,
        ],
        coverageKey: [
            (s) => [s.href, s.hrefMatchType, s.commonFilters],
            (href: string | null, hrefMatchType: HrefMatchType, commonFilters: CommonFilters): string | null =>
                href?.trim()
                    ? JSON.stringify([
                          href,
                          hrefMatchType,
                          commonFilters.date_from ?? null,
                          commonFilters.date_to ?? null,
                      ])
                    : null,
        ],
        urlDiagnosisKey: [
            (s) => [s.href, s.hrefMatchType, s.sourceUrl],
            (href: string | null, hrefMatchType: HrefMatchType, sourceUrl: string | null): string | null =>
                href?.trim() && sourceUrl ? JSON.stringify([href, hrefMatchType, sourceUrl]) : null,
        ],
        coverageIsCurrent: [
            (s) => [s.coverage, s.coverageKey],
            (
                coverage: {
                    key: string
                    rows: HeatmapCoverageRow[]
                } | null,
                coverageKey: string | null
            ): boolean => !!coverage && coverage.key === coverageKey,
        ],
        widthShares: [
            (s) => [s.coverage, s.coverageIsCurrent, s.heatmapFilters],
            (
                coverage: {
                    key: string
                    rows: HeatmapCoverageRow[]
                } | null,
                coverageIsCurrent: boolean,
                heatmapFilters: HeatmapFilters
            ): Record<number, number> | null =>
                coverage &&
                coverageIsCurrent &&
                coverage.rows.some((row) => row.type === (heatmapFilters.type ?? 'click'))
                    ? computeWidthShares(
                          coverage.rows,
                          heatmapFilters.type ?? 'click',
                          heatmapFilters,
                          HEATMAP_PRESET_WIDTHS
                      )
                    : null,
        ],
        needsUrlDiagnosis: [
            (s) => [s.heatmapEmpty, s.coverage, s.coverageIsCurrent],
            (
                heatmapEmpty: boolean,
                coverage: {
                    key: string
                    rows: HeatmapCoverageRow[]
                } | null,
                coverageIsCurrent: boolean
            ): boolean => heatmapEmpty && coverageIsCurrent && coverage?.rows.length === 0,
        ],
        emptyDiagnosisLoading: [
            (s) => [s.heatmapEmpty, s.coverageLoading, s.needsUrlDiagnosis, s.urlDiagnosisLoading],
            (
                heatmapEmpty: boolean,
                coverageLoading: boolean,
                needsUrlDiagnosis: boolean,
                urlDiagnosisLoading: boolean
            ): boolean => heatmapEmpty && (coverageLoading || (needsUrlDiagnosis && urlDiagnosisLoading)),
        ],
        emptyDiagnosis: [
            (s) => [
                s.heatmapEmpty,
                s.emptyDiagnosisLoading,
                s.coverage,
                s.coverageIsCurrent,
                s.needsUrlDiagnosis,
                s.urlDiagnosis,
                s.urlDiagnosisKey,
                s.heatmapFilters,
                s.analysisWidth,
                s.currentTeam,
            ],
            (
                heatmapEmpty: boolean,
                emptyDiagnosisLoading: boolean,
                coverage: {
                    key: string
                    rows: HeatmapCoverageRow[]
                } | null,
                coverageIsCurrent: boolean,
                needsUrlDiagnosis: boolean,
                urlDiagnosis: (HeatmapUrlDiagnosis & { key: string }) | null,
                urlDiagnosisKey: string | null,
                heatmapFilters: HeatmapFilters,
                analysisWidth: number,
                currentTeam: TeamPublicType | TeamType | null
            ): HeatmapEmptyDiagnosis | null => {
                const urlDiagnosisIsCurrent = !!urlDiagnosis && urlDiagnosis.key === urlDiagnosisKey
                if (
                    !heatmapEmpty ||
                    emptyDiagnosisLoading ||
                    !coverage ||
                    !coverageIsCurrent ||
                    (needsUrlDiagnosis && !urlDiagnosisIsCurrent)
                ) {
                    return null
                }
                return diagnoseEmptyHeatmap({
                    captureEnabled: currentTeam?.heatmaps_opt_in !== false,
                    rows: coverage.rows,
                    type: heatmapFilters.type ?? 'click',
                    heatmapFilters,
                    analysisWidth,
                    urlDiagnosis: urlDiagnosisIsCurrent ? urlDiagnosis : null,
                })
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadHeatmapSuccess: () => {
            actions.loadCoverage(null)
        },
        loadCoverageSuccess: () => {
            if (values.needsUrlDiagnosis) {
                actions.loadUrlDiagnosis(null)
                return
            }
            actions.reportEmptyDiagnosis()
        },
        loadUrlDiagnosisSuccess: () => {
            actions.reportEmptyDiagnosis()
        },
        reportEmptyDiagnosis: () => {
            const diagnosis = values.emptyDiagnosis
            if (!diagnosis) {
                return
            }
            const reportKey = JSON.stringify([
                values.coverageKey,
                diagnosis.reason,
                values.analysisWidth,
                values.heatmapFilters.type,
            ])
            if (cache.lastReportKey === reportKey) {
                return
            }
            cache.lastReportKey = reportKey
            posthog.capture('in-app heatmap empty result', {
                empty_reason: diagnosis.reason,
                match_type: values.hrefMatchType,
                url_match_mode: values.hasValidReplayIframeData ? values.recordingUrlMatchMode : null,
                analysis_width: values.analysisWidth,
                heatmap_type: values.heatmapFilters.type ?? 'click',
                has_query_string: !!values.sourceUrl?.includes('?'),
                from_recording: values.hasValidReplayIframeData,
            })
        },
        applySuggestion: ({ url }) => {
            const diagnosis = values.emptyDiagnosis
            if (!diagnosis) {
                return
            }
            posthog.capture('in-app heatmap empty suggestion applied', { suggestion: diagnosis.reason })
            if (diagnosis.reason === 'other_widths') {
                actions.setWindowWidthOverride(diagnosis.width)
            } else if (diagnosis.reason === 'other_types') {
                actions.patchHeatmapFilters({ type: diagnosis.type })
            } else if (diagnosis.reason === 'other_query_strings' && values.hasValidReplayIframeData) {
                actions.setRecordingUrlMatchMode('page')
            } else if (diagnosis.reason === 'similar_urls' && url) {
                if (values.hasValidReplayIframeData) {
                    actions.setReplayIframeDataURL(url)
                } else {
                    actions.setDataUrl(url)
                }
            }
        },
    })),
])
