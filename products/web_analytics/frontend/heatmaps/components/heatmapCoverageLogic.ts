const QUERY_TAGS = { scene: 'Heatmaps', productKey: 'heatmaps' } as const

const urlPredicate = (href: string, matchType: 'exact' | 'pattern'): string =>
    matchType === 'pattern'
        ? hogql`match(current_url, ${heatmapUrlPatternToRegex(href)})`
        : hogql`trimRight(current_url, '/') = trimRight(${href}, '/')`

const relatedUrlPredicate = (sourceUrl: string, page: string | null): string => {
    if (hasWildcard(sourceUrl)) {
        return hogql`startsWith(current_url, ${sourceUrl.split('*')[0]})`
    }
    if (!page) {
        return hogql`startsWith(current_url, ${sourceUrl})`
    }
    return hogql`(current_url = ${page} OR startsWith(current_url, ${`${page}/`}) OR startsWith(current_url, ${`${page}?`}) OR startsWith(current_url, ${`${page}#`}))`
}

