export const heatmapScreenshotSettingsLogic = kea<heatmapScreenshotSettingsLogicType>([
    props({} as HeatmapScreenshotSettingsLogicProps),
    key((props) => props.teamId),
    path((key) => ['products', 'web_analytics', 'heatmaps', 'heatmapScreenshotSettingsLogic', key]),
    connect({ values: [teamLogic, ['currentTeam']], actions: [teamLogic, ['loadCurrentTeam']] }),
    actions({ setHostnames: (hostnames: string[]) => ({ hostnames }) }),
    loaders(({ props, values, actions }) => ({
        settings: [
            null as HeatmapScreenshotSettingsApi | null,
            {
                loadSettings: async () => api.heatmapScreenshotSettingsRetrieve(String(props.teamId)),
                saveSettings: async () => {
                    const result = await api.heatmapScreenshotSettingsUpdate(String(props.teamId), {
                        allowed_hostnames: values.hostnames,
                    })
                    lemonToast.success('Approved screenshot hostnames saved.')
                    return result
                },
            },
        ],
        rotatedSecret: [
            null as string | null,
            {
                rotateSecret: async () => {
                    const team = values.currentTeam
                    if (!isAuthenticatedTeam(team) || team.id !== props.teamId) {
                        throw new Error('Project changed. Reload these settings and try again.')
                    }
                    const result = await coreApi.organizationsProjectsRotateHeatmapsScreenshotSecretPartialUpdate(
                        team.organization,
                        team.project_id
                    )
                    actions.loadCurrentTeam()
                    actions.loadSettings()
                    lemonToast.success('New value ready. Replace the old value in your bot protection rule.')
                    return result.heatmaps_screenshot_secret ?? null
                },
            },
        ],
    })),
    reducers({
        hostnames: [
            [] as string[],
            {
                setHostnames: (_, { hostnames }) => hostnames,
                loadSettingsSuccess: (_, { settings }) => settings.allowed_hostnames,
                saveSettingsSuccess: (_, { settings }) => settings.allowed_hostnames,
            },
        ],
        loadError: [
            false,
            { loadSettings: () => false, loadSettingsFailure: () => true, loadSettingsSuccess: () => false },
        ],
        saveError: [
            null as string | null,
            { saveSettings: () => null, saveSettingsFailure: (_, { error }) => error, setHostnames: () => null },
        ],
    }),
    selectors({
        secret: [
            (s) => [s.currentTeam, s.rotatedSecret],
            (team: TeamPublicType | TeamType | null, rotatedSecret: string | null): string | null =>
                rotatedSecret ?? (isAuthenticatedTeam(team) ? (team.heatmaps_screenshot_secret ?? null) : null),
        ],
        suggestions: [
            (s) => [s.currentTeam],
            (team: TeamPublicType | TeamType | null): string[] =>
                screenshotHostnameSuggestions(isAuthenticatedTeam(team) ? team.app_urls : []),
        ],
        hasChanges: [
            (s) => [s.settings, s.hostnames],
            (settings: HeatmapScreenshotSettingsApi | null, hostnames: string[]): boolean =>
                JSON.stringify(settings?.allowed_hostnames) !== JSON.stringify(hostnames),
        ],
    }),
    afterMount(({ actions, props }) => {
        if (props.teamId) {
            actions.loadSettings()
        }
    }),
])
