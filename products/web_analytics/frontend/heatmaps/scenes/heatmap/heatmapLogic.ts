function withSavedHeatmap(
    items: HeatmapScreenshotType[],
    updated: HeatmapScreenshotResponseApi
): HeatmapScreenshotType[] {
    const settings = normalizeHeatmapSettings(updated)
    return items.map((item) =>
        item.short_id === updated.short_id ? { ...item, ...settings, type: settings.type as HeatmapType } : item
    )
}

function getApiErrorMessage(error: unknown, fallback: string): string {
    if (typeof error === 'object' && error !== null && 'detail' in error && typeof error.detail === 'string') {
        return error.detail
    }
    return fallback
}

function getCreationFailureCategory(error: unknown): 'validation' | 'permission' | 'rate_limit' | 'unknown' {
    if (typeof error !== 'object' || error === null || !('status' in error) || typeof error.status !== 'number') {
        return 'unknown'
    }
    if (error.status === 400) {
        return 'validation'
    }
    if (error.status === 401 || error.status === 403) {
        return 'permission'
    }
    if (error.status === 429) {
        return 'rate_limit'
    }
    return 'unknown'
}

