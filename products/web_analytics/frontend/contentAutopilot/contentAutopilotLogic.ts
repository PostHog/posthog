export type ContentAutopilotOnboardingStep = 'site' | 'sources'

export type ContentAutopilotWorkspaceTab = 'overview' | 'rankings' | 'prompts' | 'keywords' | 'settings'
export type ContentAutopilotWorkspaceResource = 'profiles'
export type ContentAutopilotWorkspaceErrors = Partial<Record<ContentAutopilotWorkspaceResource, string>>
export type ContentAutopilotWorkspaceSettled = Record<ContentAutopilotWorkspaceResource, boolean>

export interface ContentAutopilotProfileDraft {
    name: string
    domain: string
    sourceUrls: string
    contentBoundaries: string
    brandRules: string
}

const EMPTY_PROFILE_DRAFT: ContentAutopilotProfileDraft = {
    name: '',
    domain: '',
    sourceUrls: '',
    contentBoundaries: '/',
    brandRules: '',
}

const WORKSPACE_PAGE_LIMIT = 100
const EMPTY_WORKSPACE_SETTLED: ContentAutopilotWorkspaceSettled = {
    profiles: false,
}

interface PaginatedResults<T> {
    count: number
    results: T[]
}

const fetchAllPages = async <T>(
    loadPage: (offset: number, limit: number) => Promise<PaginatedResults<T>>
): Promise<T[]> => {
    const collected: T[] = []
    for (;;) {
        const page = await loadPage(collected.length, WORKSPACE_PAGE_LIMIT)
        collected.push(...page.results)
        if (page.results.length === 0 || collected.length >= page.count) {
            return collected
        }
    }
}

const withoutWorkspaceError = (
    errors: ContentAutopilotWorkspaceErrors,
    resource: ContentAutopilotWorkspaceResource
): ContentAutopilotWorkspaceErrors => {
    const nextErrors = { ...errors }
    delete nextErrors[resource]
    return nextErrors
}

const splitLines = (value: string): string[] =>
    value
        .split('\n')
        .map((line) => line.trim())
        .filter(Boolean)

const draftFromProfile = (profile: ContentAutopilotSiteProfileApi): ContentAutopilotProfileDraft => ({
    name: profile.name ?? '',
    domain: profile.domain,
    sourceUrls: profile.source_urls.join('\n'),
    contentBoundaries: profile.content_boundaries.join('\n'),
    brandRules: profile.brand_rules.join('\n'),
})

const getErrorMessage = (error: unknown): string => {
    if (error instanceof Error) {
        return error.message
    }
    if (typeof error === 'object' && error !== null && 'detail' in error && typeof error.detail === 'string') {
        return error.detail
    }
    return 'Something went wrong. Try again.'
}

const toastClientError = (error: unknown): void => {
    if (!(error instanceof ApiError) || error.status === undefined) {
        lemonToast.error(getErrorMessage(error))
    }
}

