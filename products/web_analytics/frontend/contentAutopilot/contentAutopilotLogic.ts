export const contentAutopilotLogic = kea<contentAutopilotLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamIdStrict']] })),
    actions({
        loadWorkspace: true,
        loadSiteProfiles: true,
        beginOnboarding: true,
        cancelOnboarding: true,
        selectProfile: (profileId: string) => ({ profileId }),
        setOnboardingStep: (onboardingStep: ContentAutopilotOnboardingStep) => ({ onboardingStep }),
        resetProfileDraft: (profileDraft: ContentAutopilotProfileDraft) => ({ profileDraft }),
        setProfileDraft: (profileDraft: Partial<ContentAutopilotProfileDraft>) => ({ profileDraft }),
        setWorkspaceTab: (workspaceTab: ContentAutopilotWorkspaceTab) => ({ workspaceTab }),
    }),
    reducers({
        profileDraft: [
            EMPTY_PROFILE_DRAFT,
            {
                resetProfileDraft: (_, { profileDraft }) => profileDraft,
                setProfileDraft: (state, { profileDraft }) => ({ ...state, ...profileDraft }),
            },
        ],
        selectedProfileId: [
            null as string | null,
            {
                selectProfile: (_, { profileId }) => profileId,
                saveProfileSuccess: (_, { savedProfile }) => savedProfile.id,
                deleteProfileSuccess: () => null,
            },
        ],
        onboardingOpen: [
            false,
            {
                beginOnboarding: () => true,
                cancelOnboarding: () => false,
                saveProfileSuccess: () => false,
            },
        ],
        onboardingStep: [
            'site' as ContentAutopilotOnboardingStep,
            {
                beginOnboarding: () => 'site',
                setOnboardingStep: (_, { onboardingStep }) => onboardingStep,
                discoverSiteSuccess: () => 'sources',
            },
        ],
        workspaceTab: [
            'overview' as ContentAutopilotWorkspaceTab,
            {
                setWorkspaceTab: (_, { workspaceTab }) => workspaceTab,
                deleteProfileSuccess: () => 'overview',
            },
        ],
        workspaceSettled: [
            EMPTY_WORKSPACE_SETTLED,
            {
                loadWorkspace: () => EMPTY_WORKSPACE_SETTLED,
                loadSiteProfilesSuccess: (state) => ({ ...state, profiles: true }),
                loadSiteProfilesFailure: (state) => ({ ...state, profiles: true }),
            },
        ],
        workspaceErrors: [
            {} as ContentAutopilotWorkspaceErrors,
            {
                loadWorkspace: () => ({}),
                loadSiteProfilesSuccess: (state) => withoutWorkspaceError(state, 'profiles'),
                loadSiteProfilesFailure: (state, { errorObject }) => ({
                    ...state,
                    profiles: getErrorMessage(errorObject),
                }),
            },
        ],
    }),
    loaders(({ values }) => ({
        siteProfiles: [
            [] as ContentAutopilotSiteProfileApi[],
            {
                loadSiteProfiles: async (_, breakpoint) => {
                    const profiles = await fetchAllPages((offset, limit) =>
                        webAnalyticsApi.webAnalyticsContentAutopilotProfilesList(String(values.currentTeamIdStrict), {
                            limit,
                            offset,
                        })
                    )
                    breakpoint()
                    return profiles
                },
            },
        ],
        discoveredSite: [
            null as ContentAutopilotSiteDiscoveryResponseApi | null,
            {
                discoverSite: async () =>
                    await webAnalyticsApi.webAnalyticsContentAutopilotProfilesDiscover(
                        String(values.currentTeamIdStrict),
                        {
                            domain: values.profileDraft.domain.trim(),
                        }
                    ),
            },
        ],
        savedProfile: [
            null as ContentAutopilotSiteProfileApi | null,
            {
                saveProfile: async () => {
                    const payload = {
                        name: values.profileDraft.name.trim(),
                        domain: values.profileDraft.domain.trim(),
                        source_urls: splitLines(values.profileDraft.sourceUrls),
                        content_boundaries: splitLines(values.profileDraft.contentBoundaries),
                        brand_rules: splitLines(values.profileDraft.brandRules),
                    }
                    const profile = values.onboardingOpen ? null : values.profile
                    if (profile) {
                        return await webAnalyticsApi.webAnalyticsContentAutopilotProfilesPartialUpdate(
                            String(values.currentTeamIdStrict),
                            profile.id,
                            payload
                        )
                    }
                    return await webAnalyticsApi.webAnalyticsContentAutopilotProfilesCreate(
                        String(values.currentTeamIdStrict),
                        payload
                    )
                },
            },
        ],
        deletedProfile: [
            null as string | null,
            {
                deleteProfile: async (profileId: string) => {
                    await webAnalyticsApi.webAnalyticsContentAutopilotProfilesDestroy(
                        String(values.currentTeamIdStrict),
                        profileId
                    )
                    return profileId
                },
            },
        ],
    })),
    selectors({
        profile: [
            (selectors) => [selectors.siteProfiles, selectors.selectedProfileId],
            (
                siteProfiles: ContentAutopilotSiteProfileApi[],
                selectedProfileId: string | null
            ): ContentAutopilotSiteProfileApi | null =>
                siteProfiles.find(({ id }) => id === selectedProfileId) ?? siteProfiles[0] ?? null,
        ],
        workspaceInitialized: [
            (selectors) => [selectors.workspaceSettled],
            (workspaceSettled: ContentAutopilotWorkspaceSettled): boolean =>
                Object.values(workspaceSettled).every(Boolean),
        ],
        workspaceError: [
            (selectors) => [selectors.workspaceErrors],
            (workspaceErrors: ContentAutopilotWorkspaceErrors): string | null =>
                Object.values(workspaceErrors).join(' ') || null,
        ],
    }),
    listeners(({ actions, values }) => ({
        loadWorkspace: () => {
            actions.loadSiteProfiles()
        },
        beginOnboarding: () => {
            actions.resetProfileDraft(EMPTY_PROFILE_DRAFT)
        },
        cancelOnboarding: () => {
            if (values.profile) {
                actions.resetProfileDraft(draftFromProfile(values.profile))
            }
        },
        selectProfile: ({ profileId }) => {
            const profile = values.siteProfiles.find(({ id }) => id === profileId)
            if (profile) {
                actions.resetProfileDraft(draftFromProfile(profile))
            }
        },
        loadSiteProfilesSuccess: () => {
            if (values.profile) {
                actions.selectProfile(values.profile.id)
            } else {
                actions.beginOnboarding()
            }
        },
        discoverSiteSuccess: ({ discoveredSite }) => {
            actions.setProfileDraft({
                name: discoveredSite.name,
                domain: discoveredSite.domain,
                sourceUrls: discoveredSite.source_urls.join('\n'),
                contentBoundaries: discoveredSite.content_boundaries.join('\n'),
            })
        },
        discoverSiteFailure: ({ errorObject }) => {
            toastClientError(errorObject)
        },
        saveProfileSuccess: ({ savedProfile }) => {
            lemonToast.success('Site profile saved')
            actions.resetProfileDraft(draftFromProfile(savedProfile))
            actions.loadSiteProfiles()
        },
        saveProfileFailure: ({ errorObject }) => {
            toastClientError(errorObject)
        },
        deleteProfileSuccess: () => {
            lemonToast.success('Site deleted')
            actions.loadSiteProfiles()
        },
        deleteProfileFailure: ({ errorObject }) => {
            toastClientError(errorObject)
        },
    })),
    afterMount(({ actions }) => {
        actions.loadWorkspace()
    }),
])
