import { MakeLogicType, actions, kea, path, reducers } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { urls } from 'scenes/urls'

export type ContentAutopilotWorkspaceTab = 'overview' | 'rankings' | 'prompts' | 'keywords' | 'settings'

const WORKSPACE_TABS: ContentAutopilotWorkspaceTab[] = ['overview', 'rankings', 'prompts', 'keywords', 'settings']

const tabFromParam = (value: unknown): ContentAutopilotWorkspaceTab =>
    WORKSPACE_TABS.includes(value as ContentAutopilotWorkspaceTab)
        ? (value as ContentAutopilotWorkspaceTab)
        : 'overview'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotLogicValues {
    workspaceTab: ContentAutopilotWorkspaceTab
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotLogicActions {
    setWorkspaceTab: (workspaceTab: ContentAutopilotWorkspaceTab) => {
        workspaceTab: ContentAutopilotWorkspaceTab
    }
}

export type contentAutopilotLogicType = MakeLogicType<contentAutopilotLogicValues, contentAutopilotLogicActions>

export const contentAutopilotLogic = kea<contentAutopilotLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotLogic']),
    actions({
        setWorkspaceTab: (workspaceTab: ContentAutopilotWorkspaceTab) => ({ workspaceTab }),
    }),
    reducers({
        workspaceTab: [
            'overview' as ContentAutopilotWorkspaceTab,
            { setWorkspaceTab: (_, { workspaceTab }) => workspaceTab },
        ],
    }),
    actionToUrl(() => ({
        setWorkspaceTab: ({ workspaceTab }) => {
            const { tab: _, ...searchParams } = router.values.searchParams
            // pinned: the `tab` search param is a URL others bookmark and link to
            return [
                urls.webAnalyticsContentAutopilot(),
                workspaceTab === 'overview' ? searchParams : { ...searchParams, tab: workspaceTab },
            ]
        },
    })),
    urlToAction(({ actions, values }) => ({
        '/web/ai-visibility': (_, searchParams) => {
            const tab = tabFromParam(searchParams.tab)
            if (tab !== values.workspaceTab) {
                actions.setWorkspaceTab(tab)
            }
        },
    })),
])
