interface PaginatedResults<T> {
    count: number
    results: T[]
}

const UNDRAFTABLE_STATUSES = new Set<ContentAutopilotOpportunityApi['status']>(['queued', 'dismissed'])

const fetchAllPages = async <T>(
    loadPage: (offset: number, limit: number) => Promise<PaginatedResults<T>>
): Promise<T[]> => {
    const collected: T[] = []
    for (;;) {
        const page = await loadPage(collected.length, WORKSPACE_PAGE_LIMIT)
        collected.push(...page.results)
        if (page.results.length === 0 || collected.length >= page.count) {
            return collected
        }
    }
}

const fetchOpportunities = (teamId: string, profileId: string): Promise<ContentAutopilotOpportunityApi[]> =>
    fetchAllPages((offset, limit) =>
        webAnalyticsApi.webAnalyticsContentAutopilotOpportunitiesList(teamId, { limit, offset, profile_id: profileId })
    )

const draftableSelection = (selectedIds: string[], opportunities: ContentAutopilotOpportunityApi[]): string[] =>
    selectedIds.filter((id) =>
        opportunities.some((opportunity) => opportunity.id === id && !UNDRAFTABLE_STATUSES.has(opportunity.status))
    )

const withoutWorkspaceError = (
    errors: ContentAutopilotWorkspaceErrors,
    resource: ContentAutopilotWorkspaceResource
): ContentAutopilotWorkspaceErrors => {
    const nextErrors = { ...errors }
    delete nextErrors[resource]
    return nextErrors
}

const splitLines = (value: string): string[] =>
    value
        .split('\n')
        .map((line) => line.trim())
        .filter(Boolean)

const draftFromProfile = (profile: ContentAutopilotSiteProfileApi): ContentAutopilotProfileDraft => ({
    name: profile.name ?? '',
    domain: profile.domain,
    sourceUrls: profile.source_urls.join('\n'),
    contentBoundaries: profile.content_boundaries.join('\n'),
    brandRules: profile.brand_rules.join('\n'),
    searchConsoleEnabled: profile.search_console_enabled ?? true,
})

const getErrorMessage = (error: unknown): string => {
    if (error instanceof Error) {
        return error.message
    }
    if (typeof error === 'object' && error !== null && 'detail' in error && typeof error.detail === 'string') {
        return error.detail
    }
    return 'Something went wrong. Try again.'
}

