import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
} from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'

import { aeoPromptsSearchDetail } from 'products/web_analytics/frontend/generated/api'
import type {
    AEOPromptSetSearchDetailApi,
    BrandedSegmentEnumApi,
} from 'products/web_analytics/frontend/generated/api.schemas'

export type SearchDetailTab = 'sites' | 'searches' | 'prompts'

/** One search of the overview, read over the same window and filters the overview counted. */
export interface ContentAutopilotSearchDetailLogicProps {
    query: string
    dateFrom: string
    dateTo: string
    branded: BrandedSegmentEnumApi
    engine: string | null
    topic: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotSearchDetailLogicValues {
    currentTeamIdStrict: number | string // teamLogic
    detail: AEOPromptSetSearchDetailApi | null
    detailFailed: boolean
    detailLoading: boolean
    tab: SearchDetailTab
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotSearchDetailLogicActions {
    loadDetail: () => any
    loadDetailFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadDetailSuccess: (
        detail: AEOPromptSetSearchDetailApi,
        payload?: any
    ) => {
        detail: AEOPromptSetSearchDetailApi
        payload?: any
    }
    setTab: (tab: SearchDetailTab) => {
        tab: SearchDetailTab
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotSearchDetailLogicMeta {
    key: string
}

export type contentAutopilotSearchDetailLogicType = MakeLogicType<
    contentAutopilotSearchDetailLogicValues,
    contentAutopilotSearchDetailLogicActions,
    ContentAutopilotSearchDetailLogicProps,
    contentAutopilotSearchDetailLogicMeta
>

export const contentAutopilotSearchDetailLogic: LogicWrapper<contentAutopilotSearchDetailLogicType> =
    kea<contentAutopilotSearchDetailLogicType>([
        props({} as ContentAutopilotSearchDetailLogicProps),
        // A filter change gives the row a new key, so a reopened row never shows the counts of another window.
        key(({ query, dateFrom, dateTo, branded, engine, topic }) =>
            JSON.stringify([query, dateFrom, dateTo, branded, engine, topic])
        ),
        path((key) => ['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotSearchDetailLogic', key]),
        connect(() => ({ values: [teamLogic, ['currentTeamIdStrict']] })),
        actions({
            setTab: (tab: SearchDetailTab) => ({ tab }),
        }),
        loaders(({ props, values }) => ({
            detail: [
                null as AEOPromptSetSearchDetailApi | null,
                {
                    loadDetail: async () =>
                        await aeoPromptsSearchDetail(String(values.currentTeamIdStrict), {
                            search: props.query,
                            date_from: props.dateFrom,
                            date_to: props.dateTo,
                            branded: props.branded,
                            // An unset filter is left out: the client would send null as the text 'null'.
                            ...(props.engine !== null ? { engine: props.engine } : {}),
                            ...(props.topic !== null ? { topic: props.topic } : {}),
                        }),
                },
            ],
        })),
        reducers({
            tab: ['sites' as SearchDetailTab, { setTab: (_, { tab }) => tab }],
            detailFailed: [false, { loadDetail: () => false, loadDetailFailure: () => true }],
        }),
        listeners(() => ({
            setTab: ({ tab }) => {
                // pinned: analytics event name and property - renaming breaks dashboards
                posthog.capture('web analytics ai visibility search detail tab changed', { tab })
            },
        })),
        afterMount(({ actions }) => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('web analytics ai visibility search detail opened')
            actions.loadDetail()
        }),
    ])
