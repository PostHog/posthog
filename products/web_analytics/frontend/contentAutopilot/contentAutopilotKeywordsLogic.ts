export const contentAutopilotKeywordsLogic = kea<contentAutopilotKeywordsLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotKeywordsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
    })),
    actions({
        loadKeywords: true,
        loadReport: true,
        loadModifiers: true,
        setKeywordsDraft: (draft: string) => ({ draft }),
        addKeywords: true,
        addKeywordsSuccess: (result: AEOKeywordCreateResultApi) => ({ result }),
        addKeywordsFailure: true,
        removeKeyword: (keyword: AEOKeywordApi) => ({ keyword }),
        removeKeywordSuccess: (keyword: AEOKeywordApi) => ({ keyword }),
        removeKeywordFailure: (keyword: AEOKeywordApi) => ({ keyword }),
        setModifierKeyword: (modifierKeyword: string | null) => ({ modifierKeyword }),
    }),
    loaders(({ values }) => ({
        keywords: [
            null as AEOKeywordApi[] | null,
            {
                loadKeywords: async (_, breakpoint) => {
                    try {
                        const keywords = await aeoKeywordsList(String(values.currentTeamIdStrict))
                        breakpoint()
                        return keywords
                    } catch (error) {
                        // A superseded request's failure must not replace a newer list with an error
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
        report: [
            null as AEOKeywordReportApi | null,
            {
                loadReport: async (_, breakpoint) => {
                    // Every add and removal reloads the report, and each request runs the whole keyword query,
                    // so a quick run of removals waits here and sends only the last one.
                    await breakpoint(300)
                    try {
                        const report = await aeoKeywordsReport(String(values.currentTeamIdStrict), {
                            days: KEYWORDS_DAYS,
                        })
                        breakpoint()
                        return report
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
        modifiers: [
            null as AEOKeywordModifierReportApi | null,
            {
                loadModifiers: async (_, breakpoint) => {
                    try {
                        const modifiers = await aeoKeywordsModifiers(String(values.currentTeamIdStrict), {
                            days: KEYWORDS_DAYS,
                            keyword: values.modifierKeyword ?? undefined,
                        })
                        breakpoint()
                        return modifiers
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        keywords: {
            removeKeywordSuccess: (state, { keyword }) => state?.filter(({ id }) => id !== keyword.id) ?? null,
        },
        keywordsDraft: [
            '',
            {
                setKeywordsDraft: (_, { draft }) => draft,
                addKeywordsSuccess: () => '',
            },
        ],
        addKeywordsSubmitting: [
            false,
            {
                addKeywords: () => true,
                addKeywordsSuccess: () => false,
                addKeywordsFailure: () => false,
            },
        ],
        keywordRemoving: [
            {} as Record<string, boolean>,
            {
                removeKeyword: (state, { keyword }) => ({ ...state, [keyword.id]: true }),
                removeKeywordSuccess: (state, { keyword }) => omitKey(state, keyword.id),
                removeKeywordFailure: (state, { keyword }) => omitKey(state, keyword.id),
            },
        ],
        modifierKeyword: [
            null as string | null,
            {
                setModifierKeyword: (_, { modifierKeyword }) => modifierKeyword,
            },
        ],
        keywordsError: [
            null as ContentAutopilotPromptsError | null,
            {
                loadKeywords: () => null,
                loadKeywordsFailure: (_, { errorObject }) => promptsErrorFrom(errorObject),
            },
        ],
        reportError: [
            null as ContentAutopilotPromptsError | null,
            {
                loadReport: () => null,
                loadReportFailure: (_, { errorObject }) => promptsErrorFrom(errorObject),
            },
        ],
        modifiersError: [
            null as ContentAutopilotPromptsError | null,
            {
                loadModifiers: () => null,
                loadModifiersFailure: (_, { errorObject }) => promptsErrorFrom(errorObject),
            },
        ],
    }),
    selectors({
        draftKeywords: [(s) => [s.keywordsDraft], (draft: string): string[] => keywordLines(draft)],
        keywordsLeft: [
            (s) => [s.keywords],
            (keywords: AEOKeywordApi[] | null): number => MAX_KEYWORDS - (keywords?.length ?? 0),
        ],
        // The API skips keywords the list already has, so only the others count against the cap.
        newDraftKeywords: [
            (s) => [s.draftKeywords, s.keywords],
            (draftKeywords: string[], keywords: AEOKeywordApi[] | null): string[] => {
                const tracked = new Set(keywords?.map(({ keyword }) => keyword))
                return draftKeywords.filter((keyword) => !tracked.has(keyword))
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        addKeywords: async () => {
            try {
                const result = await aeoKeywordsCreate(String(values.currentTeamIdStrict), {
                    keywords: values.draftKeywords,
                })
                actions.addKeywordsSuccess(result)
            } catch (error) {
                actions.addKeywordsFailure()
                // A 400 says why the keywords were refused, such as the cap, so show it rather than asking for a retry.
                const detail = error instanceof ApiError && error.status === 400 ? error.detail : null
                lemonToast.error(detail || "Couldn't add the keywords. Try again.")
            }
        },
        addKeywordsSuccess: ({ result }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot keywords added', {
                created: result.created,
                skipped: result.skipped,
            })
            lemonToast.success(keywordsAddedMessage(result))
            actions.loadKeywords()
            actions.loadReport()
        },
        removeKeyword: async ({ keyword }) => {
            try {
                await aeoKeywordsDestroy(String(values.currentTeamIdStrict), keyword.id)
                actions.removeKeywordSuccess(keyword)
            } catch {
                actions.removeKeywordFailure(keyword)
                lemonToast.error(`Couldn't remove "${keyword.keyword}". Try again.`)
            }
        },
        removeKeywordSuccess: ({ keyword }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot keyword removed')
            actions.loadReport()
            if (values.modifierKeyword === keyword.keyword) {
                actions.setModifierKeyword(null)
            }
        },
        setModifierKeyword: ({ modifierKeyword }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot keywords modifier filter changed', {
                filtered: modifierKeyword !== null,
            })
            actions.loadModifiers()
        },
    })),
    afterMount(({ actions }) => {
        // pinned: analytics event name, renaming it breaks dashboards
        posthog.capture('web analytics content autopilot keywords viewed')
        actions.loadKeywords()
        actions.loadReport()
        actions.loadModifiers()
    }),
])
