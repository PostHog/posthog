import { MakeLogicType, actions, afterMount, connect, kea, listeners, path } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { aeoBrandsList, aeoPromptsOverview, aeoPromptsRankings } from 'products/web_analytics/frontend/generated/api'
import type {
    AEOPromptSetOverviewApi,
    AEOPromptSetRankingsApi,
} from 'products/web_analytics/frontend/generated/api.schemas'

import { aiVisibilityCompetitorReviewLogic } from './aiVisibilityCompetitorReviewLogic'

export interface FirstResults {
    nonBranded: AEOPromptSetOverviewApi
    branded: AEOPromptSetOverviewApi
    rankings: AEOPromptSetRankingsApi
    ownName: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiVisibilityFirstResultsLogicValues {
    currentTeamIdStrict: number | string // teamLogic
    firstResults: FirstResults | null
    firstResultsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiVisibilityFirstResultsLogicActions {
    confirmSelectedSuccess: (brandIds: string[]) => {
        brandIds: string[]
    } // aiVisibilityCompetitorReviewLogic
    loadFirstResults: () => {
        value: true
    }
    loadFirstResultsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFirstResultsSuccess: (
        firstResults: {
            branded: AEOPromptSetOverviewApi
            nonBranded: AEOPromptSetOverviewApi
            ownName: string | null
            rankings: AEOPromptSetRankingsApi
        },
        payload?: {
            value: true
        }
    ) => {
        firstResults: {
            branded: AEOPromptSetOverviewApi
            nonBranded: AEOPromptSetOverviewApi
            ownName: string | null
            rankings: AEOPromptSetRankingsApi
        }
        payload?: {
            value: true
        }
    }
}

export type aiVisibilityFirstResultsLogicType = MakeLogicType<
    aiVisibilityFirstResultsLogicValues,
    aiVisibilityFirstResultsLogicActions
>

export const aiVisibilityFirstResultsLogic = kea<aiVisibilityFirstResultsLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'aiVisibilityFirstResultsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
        actions: [aiVisibilityCompetitorReviewLogic, ['confirmSelectedSuccess']],
    })),
    actions({
        loadFirstResults: true,
    }),
    loaders(({ values }) => ({
        firstResults: [
            null as FirstResults | null,
            {
                loadFirstResults: async (_, breakpoint) => {
                    const teamId = String(values.currentTeamIdStrict)
                    // Only the current prompts, so after a reset the answers to the previous site's prompts don't count.
                    const [nonBranded, branded, rankings, own] = await Promise.all([
                        aeoPromptsOverview(teamId, { branded: 'non_branded', current_prompts: true }),
                        aeoPromptsOverview(teamId, { branded: 'branded', current_prompts: true }),
                        aeoPromptsRankings(teamId, { branded: 'non_branded', current_prompts: true }),
                        aeoBrandsList(teamId, { kind: 'own', status: 'confirmed', limit: 1 }),
                    ])
                    breakpoint()
                    return { nonBranded, branded, rankings, ownName: own.results[0]?.name || null }
                },
            },
        ],
    })),
    listeners(({ actions }) => ({
        confirmSelectedSuccess: async (_, breakpoint) => {
            await breakpoint(500)
            actions.loadFirstResults()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadFirstResults()
    }),
])
