/** How often the site appears on Google for each tracked keyword, read from the project's Search Console
 * source over the keyword report's window. */
export const contentAutopilotKeywordSearchLogic = kea<contentAutopilotKeywordSearchLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotKeywordSearchLogic']),
    connect(() => ({
        values: [
            databaseTableListLogic,
            ['dataWarehouseTables', 'database', 'databaseLoading'],
            contentAutopilotKeywordsLogic,
            ['report'],
        ],
        actions: [
            databaseTableListLogic,
            ['loadDatabase', 'loadDatabaseSuccess'],
            contentAutopilotKeywordsLogic,
            ['loadReportSuccess'],
        ],
    })),
    actions({
        loadImpressions: true,
    }),
    loaders(({ values }) => ({
        impressions: [
            null as Record<string, KeywordSearchImpressions> | null,
            {
                loadImpressions: async (_, breakpoint) => {
                    const { searchTable, report } = values
                    if (!searchTable || !report || report.keywords.length === 0) {
                        return null
                    }
                    const query: HogQLQuery = {
                        kind: NodeKind.HogQLQuery,
                        query: buildKeywordImpressionsQuery(
                            searchTable,
                            report.keywords.map(({ keyword }) => keyword),
                            { from: report.window_from, to: report.window_to }
                        ),
                        tags: WEB_ANALYTICS_DEFAULT_QUERY_TAGS,
                    }
                    try {
                        const response = await performQuery(query)
                        breakpoint()
                        return keywordImpressionsFromRows(response.results ?? [])
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        impressionsFailed: [
            false,
            {
                loadImpressions: () => false,
                loadImpressionsSuccess: () => false,
                loadImpressionsFailure: () => true,
            },
        ],
    }),
    selectors({
        searchTable: [
            (s) => [s.dataWarehouseTables],
            (dataWarehouseTables: DatabaseSchemaDataWarehouseTable[]): string | null =>
                findSearchConsoleQueryTable(dataWarehouseTables),
        ],
        // Known only once the table list has loaded, so the connect hint never shows while it is still loading.
        searchConsoleMissing: [
            (s) => [s.database, s.searchTable],
            (database: unknown, searchTable: string | null): boolean => database !== null && searchTable === null,
        ],
    }),
    listeners(({ actions }) => ({
        loadDatabaseSuccess: () => actions.loadImpressions(),
        loadReportSuccess: () => actions.loadImpressions(),
    })),
    afterMount(({ actions, values }) => {
        if (!values.database && !values.databaseLoading) {
            // Only the table names are read, so the fields are not worth fetching.
            actions.loadDatabase({ shallow: true })
        } else {
            actions.loadImpressions()
        }
    }),
])
