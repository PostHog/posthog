import { MakeLogicType, afterMount, connect, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { aeoPromptsTopics } from 'products/web_analytics/frontend/generated/api'
import type { AEOEngineSettingApi, AEOPromptTopicApi } from 'products/web_analytics/frontend/generated/api.schemas'

import { aiVisibilityEnginesLogic } from './aiVisibilityEnginesLogic'
import { topicLabel } from './aiVisibilityFilters'
import { contentAutopilotFiltersLogic } from './contentAutopilotFiltersLogic'
import { engineLabel, sortEngines } from './utils'

export interface FilterOption {
    value: string | null
    label: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotFilterBarLogicValues {
    engines: AEOEngineSettingApi[] | null // aiVisibilityEnginesLogic
    engine: string | null // contentAutopilotFiltersLogic
    topic: string | null // contentAutopilotFiltersLogic
    currentTeamIdStrict: number | string // teamLogic
    engineOptions: FilterOption[]
    promptTopics: AEOPromptTopicApi[] | null
    promptTopicsError: boolean
    promptTopicsLoading: boolean
    topicOptions: FilterOption[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotFilterBarLogicActions {
    loadPromptTopics: () => any
    loadPromptTopicsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadPromptTopicsSuccess: (
        promptTopics: AEOPromptTopicApi[],
        payload?: any
    ) => {
        promptTopics: AEOPromptTopicApi[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotFilterBarLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        engineOptions: (engines: AEOEngineSettingApi[] | null, engine: string | null) => FilterOption[]
        topicOptions: (promptTopics: AEOPromptTopicApi[] | null, topic: string | null) => FilterOption[]
    }
}

export type contentAutopilotFilterBarLogicType = MakeLogicType<
    contentAutopilotFilterBarLogicValues,
    contentAutopilotFilterBarLogicActions,
    Record<string, any>,
    contentAutopilotFilterBarLogicMeta
>

/** The engines and topics the filter bar offers. */
export const contentAutopilotFilterBarLogic = kea<contentAutopilotFilterBarLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotFilterBarLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamIdStrict'],
            aiVisibilityEnginesLogic,
            ['engines'],
            contentAutopilotFiltersLogic,
            ['engine', 'topic'],
        ],
    })),
    loaders(({ values }) => ({
        promptTopics: [
            null as AEOPromptTopicApi[] | null,
            {
                loadPromptTopics: async () => aeoPromptsTopics(String(values.currentTeamIdStrict)),
            },
        ],
    })),
    reducers({
        promptTopicsError: [
            false,
            {
                loadPromptTopics: () => false,
                loadPromptTopicsFailure: () => true,
            },
        ],
    }),
    selectors({
        engineOptions: [
            (s) => [s.engines, s.engine],
            (engines: AEOEngineSettingApi[] | null, engine: string | null): FilterOption[] => {
                // Every engine the project can turn on, since past answers stay after an engine is turned off. A
                // selected engine from a link stays listed even when the project no longer has it.
                const ids = sortEngines([
                    ...(engines ?? []).map((setting) => setting.engine),
                    ...(engine ? [engine] : []),
                ])
                return [
                    { value: null, label: 'All engines' },
                    ...ids.map((id) => ({ value: id, label: engineLabel(id) })),
                ]
            },
        ],
        topicOptions: [
            (s) => [s.promptTopics, s.topic],
            (promptTopics: AEOPromptTopicApi[] | null, topic: string | null): FilterOption[] => {
                const known = promptTopics ?? []
                return [
                    { value: null, label: 'All topics' },
                    ...known.map(({ topic: value, prompts }) => ({
                        value,
                        label: `${topicLabel(value)} (${prompts})`,
                    })),
                    // A topic from a link that no prompt has now still shows, since past answers keep their topic.
                    ...(topic !== null && !known.some((row) => row.topic === topic)
                        ? [{ value: topic, label: topicLabel(topic) }]
                        : []),
                ]
            },
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadPromptTopics()
    }),
])
