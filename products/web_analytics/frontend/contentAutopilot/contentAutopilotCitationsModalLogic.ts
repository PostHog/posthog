/** The answers behind one cited page, cited site or engine search, shown in one modal for the whole page. */
export const contentAutopilotCitationsModalLogic = kea<contentAutopilotCitationsModalLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotCitationsModalLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
        actions: [contentAutopilotLogic, ['setWorkspaceTab'], contentAutopilotPromptDetailLogic, ['openPromptDetail']],
    })),
    actions({
        openCitations: (lookup: CitationsLookup, source: string) => ({ lookup, source }),
        closeCitations: true,
        loadCitations: true,
        loadMoreCitations: true,
        openCitationPrompt: (promptId: string) => ({ promptId }),
    }),
    reducers({
        lookup: [
            null as CitationsLookup | null,
            {
                openCitations: (_, { lookup }) => lookup,
                closeCitations: () => null,
            },
        ],
        citationsFailed: [
            false,
            {
                loadCitations: () => false,
                loadMoreCitations: () => false,
                loadCitationsFailure: () => true,
                loadMoreCitationsFailure: () => true,
            },
        ],
        // Opening another lookup clears the list, so the previous lookup's rows never show under its title.
        citations: {
            openCitations: () => null,
            closeCitations: () => null,
        },
    }),
    loaders(({ values }) => {
        const fetchPage = async (offset: number): Promise<PaginatedAEOPromptCitationListApi | null> => {
            const lookup = values.lookup
            if (!lookup) {
                return null
            }
            return await aeoPromptsCitations(String(values.currentTeamIdStrict), {
                [lookup.kind]: lookup.value,
                days: lookup.days,
                branded: lookup.branded,
                include_answer_text: true,
                limit: CITATIONS_PAGE_SIZE,
                offset,
            })
        }
        return {
            citations: [
                null as CitationsPage | null,
                {
                    loadCitations: async (_, breakpoint): Promise<CitationsPage | null> => {
                        const page = await fetchPage(0)
                        breakpoint()
                        return page ? { results: page.results, count: page.count } : null
                    },
                    loadMoreCitations: async (_, breakpoint): Promise<CitationsPage | null> => {
                        const loaded = values.citations
                        if (!loaded) {
                            return null
                        }
                        const page = await fetchPage(loaded.results.length)
                        breakpoint()
                        return page ? { results: [...loaded.results, ...page.results], count: page.count } : loaded
                    },
                },
            ],
        }
    }),
    selectors({
        hasMoreCitations: [
            (s) => [s.citations],
            (citations: CitationsPage | null): boolean => !!citations && citations.results.length < citations.count,
        ],
        isOwnPage: [
            (s) => [s.lookup, s.citations],
            (lookup: CitationsLookup | null, citations: CitationsPage | null): boolean =>
                lookup?.kind === 'url' &&
                !!citations?.results.some((citation) => citation.target_urls.includes(lookup.value)),
        ],
    }),
    listeners(({ actions }) => ({
        openCitations: ({ lookup, source }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot citations opened', { kind: lookup.kind, source })
            actions.loadCitations()
        },
        openCitationPrompt: ({ promptId }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot citations prompt opened')
            actions.closeCitations()
            actions.setWorkspaceTab('prompts')
            actions.openPromptDetail(promptId)
        },
    })),
])
