export type BrandDetailTab = 'prompts' | 'citations' | 'sentiment' | 'searches'

export type BrandDetailError = 'not_found' | 'forbidden' | 'failed'

// The kinds the picker offers. Domains nobody labeled stay out, as they do on the rankings.
const PICKER_KINDS = [AeoBrandsListKind.Own, AeoBrandsListKind.Competitor, AeoBrandsListKind.Publisher]
const PICKER_PAGE_SIZE = 200

const detailErrorFrom = (error: unknown): BrandDetailError =>
    error instanceof ApiError && error.status === 404
        ? 'not_found'
        : error instanceof ApiError && error.status === 403
          ? 'forbidden'
          : 'failed'

