/** One catalog brand's page, on its own URL in place of the workspace tabs, over the filters of the rankings. */
export const contentAutopilotBrandDetailLogic = kea<contentAutopilotBrandDetailLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotBrandDetailLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], contentAutopilotFiltersLogic, ['filters']],
        actions: [
            contentAutopilotFiltersLogic,
            ['setDates', 'setEngine', 'setTopic', 'setBrandedSegment', 'applyUrlFilters'],
            contentAutopilotLogic,
            ['setWorkspaceTab'],
            contentAutopilotPromptDetailLogic,
            ['openPromptDetail'],
        ],
    })),
    actions({
        openBrandDetail: (brandId: string) => ({ brandId }),
        closeBrandDetail: true,
        setTab: (tab: BrandDetailTab) => ({ tab }),
        openBrandPrompt: (promptId: string) => ({ promptId }),
        loadDetail: true,
        loadPickerBrands: true,
    }),
    loaders(({ values }) => ({
        detail: [
            null as AEOBrandDetailApi | null,
            {
                loadDetail: async (_, breakpoint) => {
                    if (!values.brandId) {
                        return null
                    }
                    try {
                        const detail = await aeoBrandsDetail(
                            String(values.currentTeamIdStrict),
                            values.brandId,
                            filtersToQueryParams(values.filters)
                        )
                        breakpoint()
                        return detail
                    } catch (error) {
                        // A superseded request's failure must not replace a newer brand with an error.
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
        pickerBrands: [
            null as AEOBrandApi[] | null,
            {
                loadPickerBrands: async () => {
                    const pages = await Promise.all(
                        PICKER_KINDS.map((kind) =>
                            aeoBrandsList(String(values.currentTeamIdStrict), { kind, limit: PICKER_PAGE_SIZE })
                        )
                    )
                    return pages.flatMap((page) => page.results)
                },
            },
        ],
    })),
    reducers({
        brandId: [
            null as string | null,
            {
                openBrandDetail: (_, { brandId }) => brandId,
                closeBrandDetail: () => null,
            },
        ],
        // Another brand's figures never show under the new brand's name while it loads.
        detail: {
            openBrandDetail: () => null,
            closeBrandDetail: () => null,
        },
        detailError: [
            null as BrandDetailError | null,
            {
                openBrandDetail: () => null,
                loadDetail: () => null,
                loadDetailFailure: (_, { errorObject }) => detailErrorFrom(errorObject),
            },
        ],
        tab: [
            'prompts' as BrandDetailTab,
            {
                setTab: (_, { tab }) => tab,
            },
        ],
    }),
    selectors({
        kpis: [
            (s) => [s.detail],
            (detail: AEOBrandDetailApi | null): BrandDetailKpi[] | null => (detail ? brandDetailKpis(detail) : null),
        ],
        pickerGroups: [
            (s) => [s.pickerBrands, s.detail],
            (pickerBrands: AEOBrandApi[] | null, detail: AEOBrandDetailApi | null): BrandPickerGroup[] =>
                brandPickerGroups(pickerBrands ?? [], detail?.brand ?? null),
        ],
    }),
    listeners(({ actions, values }) => {
        const reload = (): void => {
            if (values.brandId) {
                actions.loadDetail()
            }
        }
        return {
            openBrandDetail: () => {
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics ai visibility brand detail opened')
                actions.loadDetail()
                if (!values.pickerBrands && !values.pickerBrandsLoading) {
                    actions.loadPickerBrands()
                }
            },
            setTab: ({ tab }) => {
                // pinned: analytics event name and property, renaming them breaks dashboards
                posthog.capture('web analytics ai visibility brand detail tab changed', { tab })
            },
            openBrandPrompt: ({ promptId }) => {
                actions.setWorkspaceTab('prompts')
                actions.openPromptDetail(promptId)
            },
            // Picking a workspace tab, from the tabs or the back link, leaves the brand page.
            setWorkspaceTab: () => {
                if (values.brandId) {
                    actions.closeBrandDetail()
                }
            },
            setDates: reload,
            setEngine: reload,
            setTopic: reload,
            setBrandedSegment: reload,
            applyUrlFilters: reload,
        }
    }),
    actionToUrl(({ values }) => ({
        // Each brand has its own URL, so a brand can be linked to and the back button closes it.
        openBrandDetail: ({ brandId }) => {
            const path = urls.webAnalyticsContentAutopilotBrand(brandId)
            // The workspace tab is not part of the brand page, and going back sets it to the rankings.
            const { tab: _, ...searchParams } = router.values.searchParams
            return router.values.location.pathname.endsWith(path) ? undefined : [path, searchParams]
        },
        closeBrandDetail: () =>
            values.brandId === null && router.values.location.pathname.includes('/web/ai-visibility/brands/')
                ? [urls.webAnalyticsContentAutopilot(), { ...router.values.searchParams, tab: 'rankings' }]
                : undefined,
    })),
    urlToAction(({ actions, values }) => ({
        '/web/ai-visibility/brands/:brandId': ({ brandId }) => {
            if (brandId && brandId !== values.brandId) {
                actions.openBrandDetail(brandId)
            }
        },
        '/web/ai-visibility': () => {
            if (values.brandId) {
                actions.closeBrandDetail()
            }
        },
        '/web/ai-visibility/prompts/:promptId': () => {
            if (values.brandId) {
                actions.closeBrandDetail()
            }
        },
    })),
])
