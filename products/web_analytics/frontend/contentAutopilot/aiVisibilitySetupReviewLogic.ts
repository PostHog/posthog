const PROMPTS_LIMIT = 200

export interface ReviewKeyword {
    keyword: string
    id: string | null
}

export const mergeKeywordRows = (rows: ReviewKeyword[], loaded: AEOKeywordApi[]): ReviewKeyword[] => {
    const ids = new Map(loaded.map(({ keyword, id }) => [keyword, id]))
    const known = new Set(rows.map(({ keyword }) => keyword))
    return [
        ...rows.map(({ keyword }) => ({ keyword, id: ids.get(keyword) ?? null })),
        ...loaded.filter(({ keyword }) => !known.has(keyword)).map(({ keyword, id }) => ({ keyword, id })),
    ]
}

const withActive = (prompts: AEOPromptApi[] | null, promptId: string, active: boolean): AEOPromptApi[] | null =>
    prompts && prompts.map((prompt) => (prompt.id === promptId ? { ...prompt, active } : prompt))

const without = (state: Record<string, boolean>, key: string): Record<string, boolean> => {
    const { [key]: _, ...rest } = state
    return rest
}

const toggled = (kind: 'prompt' | 'keyword' | 'engine', on: boolean): void => {
    // pinned: analytics event name, renaming it breaks dashboards
    posthog.capture('web analytics ai visibility setup review toggled', { kind, on })
}

