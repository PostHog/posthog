export const aiVisibilitySetupReviewLogic = kea<aiVisibilitySetupReviewLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'aiVisibilitySetupReviewLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], contentAutopilotSetupLogic, ['setupContext']],
        actions: [
            contentAutopilotSetupLogic,
            ['loadSetupContext', 'setJob'],
            contentAutopilotPromptsLogic,
            ['addPromptsSuccess', 'openAddPrompts'],
        ],
    })),
    actions({
        togglePrompt: (promptId: string, active: boolean) => ({ promptId, active }),
        togglePromptDone: (promptId: string) => ({ promptId }),
        togglePromptFailure: (promptId: string, active: boolean) => ({ promptId, active }),
        toggleKeyword: (keyword: ReviewKeyword, on: boolean) => ({ keyword, on }),
        toggleKeywordDone: (keyword: string) => ({ keyword }),
        toggleEngine: (engine: string, enabled: boolean) => ({ engine, enabled }),
        setEngineFrequency: (engine: string, frequency: CheckFrequencyEnumApi) => ({ engine, frequency }),
        toggleEngineDone: (engine: string) => ({ engine }),
    }),
    loaders(({ values }) => ({
        prompts: [
            null as AEOPromptApi[] | null,
            {
                loadPrompts: async () =>
                    (await aeoPromptsList(String(values.currentTeamIdStrict), { limit: PROMPTS_LIMIT })).results,
            },
        ],
        loadedKeywords: [
            null as AEOKeywordApi[] | null,
            {
                loadKeywords: async () => await aeoKeywordsList(String(values.currentTeamIdStrict)),
            },
        ],
    })),
    reducers({
        prompts: {
            togglePrompt: (state, { promptId, active }) => withActive(state, promptId, active),
            togglePromptFailure: (state, { promptId, active }) => withActive(state, promptId, !active),
        },
        promptsFailed: [false, { loadPrompts: () => false, loadPromptsFailure: () => true }],
        keywordsFailed: [false, { loadKeywords: () => false, loadKeywordsFailure: () => true }],
        keywordRows: [
            [] as ReviewKeyword[],
            { loadKeywordsSuccess: (state, { loadedKeywords }) => mergeKeywordRows(state, loadedKeywords) },
        ],
        promptsUpdating: [
            {} as Record<string, boolean>,
            {
                togglePrompt: (state, { promptId }) => ({ ...state, [promptId]: true }),
                togglePromptDone: (state, { promptId }) => without(state, promptId),
                togglePromptFailure: (state, { promptId }) => without(state, promptId),
            },
        ],
        keywordsUpdating: [
            {} as Record<string, boolean>,
            {
                toggleKeyword: (state, { keyword }) => ({ ...state, [keyword.keyword]: true }),
                toggleKeywordDone: (state, { keyword }) => without(state, keyword),
            },
        ],
        enginesUpdating: [
            {} as Record<string, boolean>,
            {
                toggleEngine: (state, { engine }) => ({ ...state, [engine]: true }),
                setEngineFrequency: (state, { engine }) => ({ ...state, [engine]: true }),
                toggleEngineDone: (state, { engine }) => without(state, engine),
            },
        ],
    }),
    selectors({
        engines: [
            (s) => [s.setupContext],
            (context: AEOSetupContextApi | null): AEOEngineSettingApi[] =>
                context ? onboardingEngines(context.engines) : [],
        ],
        activePromptCount: [
            (s) => [s.prompts],
            (prompts: AEOPromptApi[] | null): number => (prompts ?? []).filter((prompt) => prompt.active).length,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        togglePrompt: async ({ promptId, active }) => {
            try {
                await aeoPromptsPartialUpdate(String(values.currentTeamIdStrict), promptId, { active })
                actions.togglePromptDone(promptId)
                toggled('prompt', active)
                actions.loadSetupContext()
            } catch (error) {
                actions.togglePromptFailure(promptId, active)
                const detail = error instanceof ApiError && error.status === 400 ? error.detail : null
                lemonToast.error(
                    detail ||
                        (active
                            ? "Couldn't turn the prompt on. Try again."
                            : "Couldn't turn the prompt off. Try again.")
                )
            }
        },
        toggleKeyword: async ({ keyword, on }) => {
            const teamId = String(values.currentTeamIdStrict)
            try {
                if (on) {
                    await aeoKeywordsCreate(teamId, { keywords: [keyword.keyword] })
                } else if (keyword.id) {
                    await aeoKeywordsDestroy(teamId, keyword.id)
                }
                toggled('keyword', on)
            } catch (error) {
                const detail = error instanceof ApiError && error.status === 400 ? error.detail : null
                lemonToast.error(detail || `Couldn't turn "${keyword.keyword}" ${on ? 'on' : 'off'}. Try again.`)
            }
            actions.toggleKeywordDone(keyword.keyword)
            actions.loadKeywords()
            // The restart dialog reads the keyword count from the context.
            actions.loadSetupContext()
        },
        toggleEngine: async ({ engine, enabled }) => {
            try {
                await aeoEnginesPartialUpdate(String(values.currentTeamIdStrict), engine, { enabled })
                toggled('engine', enabled)
            } catch {
                lemonToast.error("Couldn't update the engine. Try again.")
            }
            actions.toggleEngineDone(engine)
            actions.loadSetupContext()
        },
        setEngineFrequency: async ({ engine, frequency }) => {
            try {
                await aeoEnginesPartialUpdate(String(values.currentTeamIdStrict), engine, { frequency })
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics ai visibility setup review frequency', { frequency })
            } catch {
                lemonToast.error("Couldn't change how often the engine checks. Try again.")
            }
            actions.toggleEngineDone(engine)
            actions.loadSetupContext()
        },
        addPromptsSuccess: () => {
            actions.loadPrompts()
        },
        setJob: ({ job }) => {
            // Setup saves prompts and then keywords while this step is open, so the lists reload as each step ends
            // rather than on every poll.
            const finished = (job?.steps ?? [])
                .filter((step) => step.status !== 'pending' && step.status !== 'running')
                .map((step) => step.step)
                .join(',')
            if (finished !== cache.finishedSteps) {
                cache.finishedSteps = finished
                actions.loadPrompts()
                actions.loadKeywords()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadPrompts()
        actions.loadKeywords()
    }),
])
