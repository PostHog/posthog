export const contentAutopilotPromptsOverviewLogic = kea<contentAutopilotPromptsOverviewLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotPromptsOverviewLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], contentAutopilotBrandedLogic, ['brandedSegment']],
        actions: [
            contentAutopilotBrandedLogic,
            ['setBrandedSegment'],
            contentAutopilotPromptsLogic,
            ['setPromptsTopic', 'setPromptActiveSuccess', 'addPromptsSuccess'],
            contentAutopilotPromptDetailLogic,
            ['setPromptArchivedSuccess', 'savePromptEditSuccess', 'openPromptDetail'],
            contentAutopilotLogic,
            ['setWorkspaceTab'],
        ],
    })),
    actions({
        loadPromptSetOverview: true,
        selectOverviewTopic: (topic: string) => ({ topic }),
        openOverviewSearchPrompt: (promptId: string) => ({ promptId }),
        setChartMetric: (metric: PromptVisibilityMetric) => ({ metric }),
    }),
    loaders(({ values }) => ({
        overview: [
            null as AEOPromptSetOverviewApi | null,
            {
                loadPromptSetOverview: async (_, breakpoint) => {
                    try {
                        const overview = await aeoPromptsOverview(String(values.currentTeamIdStrict), {
                            days: OVERVIEW_DAYS,
                            branded: values.brandedSegment,
                        })
                        breakpoint()
                        return overview
                    } catch (error) {
                        // A superseded request's failure must not replace the newer overview with an error
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        chartMetric: [
            'cited' as PromptVisibilityMetric,
            {
                setChartMetric: (_, { metric }) => metric,
            },
        ],
        overviewError: [
            null as ContentAutopilotPromptsError | null,
            {
                loadPromptSetOverview: () => null,
                loadPromptSetOverviewFailure: (_, { errorObject }) => promptsErrorFrom(errorObject),
            },
        ],
    }),
    selectors({
        overviewKpis: [
            (s) => [s.overview],
            (overview: AEOPromptSetOverviewApi | null): PromptsOverviewKpis | null =>
                overview ? promptsOverviewKpis(overview) : null,
        ],
        topicQuadrantGroups: [
            (s) => [s.overview],
            (overview: AEOPromptSetOverviewApi | null): TopicQuadrantGroup[] | null =>
                overview && overview.current.mention_rate !== null && overview.current.citation_rate !== null
                    ? topicQuadrants(overview.topics, overview.current.mention_rate, overview.current.citation_rate)
                    : null,
        ],
        hasChecks: [
            (s) => [s.overview],
            (overview: AEOPromptSetOverviewApi | null): boolean =>
                overview ? promptsOverviewHasChecks(overview) : false,
        ],
        overviewWindow: [
            (s) => [s.overview],
            (overview: AEOPromptSetOverviewApi | null): PromptSetWindow | null =>
                overview
                    ? { from: overview.window_from, brandNames: overview.brand_names, branded: overview.branded }
                    : null,
        ],
        visibilityChart: [
            (s) => [s.overview, s.chartMetric],
            (
                overview: AEOPromptSetOverviewApi | null,
                chartMetric: PromptVisibilityMetric
            ): EngineVisibilityChart | null =>
                overview
                    ? engineVisibilityChart(
                          overview.daily,
                          statsWindowDates({ daily_from: overview.window_from, daily_to: overview.window_to }),
                          chartMetric
                      )
                    : null,
        ],
        visibilityQuery: [
            (s) => [s.overviewWindow, s.chartMetric],
            (
                overviewWindow: PromptSetWindow | null,
                chartMetric: PromptVisibilityMetric
            ): DataVisualizationNode | null =>
                overviewWindow ? promptSetVisibilityQuery(overviewWindow, chartMetric) : null,
        ],
        sourcesQuery: [
            (s) => [s.overviewWindow],
            (overviewWindow: PromptSetWindow | null): DataTableNode | null =>
                overviewWindow ? promptSetSourcesQuery(overviewWindow) : null,
        ],
    }),
    listeners(({ actions }) => ({
        selectOverviewTopic: ({ topic }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot prompts overview topic selected')
            actions.setPromptsTopic(topic)
            actions.setWorkspaceTab('prompts')
        },
        openOverviewSearchPrompt: ({ promptId }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot prompts overview search prompt opened')
            actions.setWorkspaceTab('prompts')
            actions.openPromptDetail(promptId)
        },
        setBrandedSegment: () => actions.loadPromptSetOverview(),
        // Adding, editing, turning on or off, or archiving a prompt changes the counts.
        setPromptActiveSuccess: () => actions.loadPromptSetOverview(),
        setPromptArchivedSuccess: () => actions.loadPromptSetOverview(),
        addPromptsSuccess: () => actions.loadPromptSetOverview(),
        savePromptEditSuccess: () => actions.loadPromptSetOverview(),
    })),
    afterMount(({ actions }) => {
        actions.loadPromptSetOverview()
    }),
])
