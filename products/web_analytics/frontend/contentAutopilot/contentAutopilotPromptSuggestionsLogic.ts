import {
    aeoPromptsBulkImport,
    aeoPromptsSuggest,
    aeoPromptsSuggestionRetrieve,
} from 'products/web_analytics/frontend/generated/api'
import type {
    AEOPromptImportResultApi,
    AEOPromptSuggestionApi,
    AEOPromptSuggestionJobApi,
    ContentAutopilotSiteProfileApi,
} from 'products/web_analytics/frontend/generated/api.schemas'

import { contentAutopilotLogic } from './contentAutopilotLogic'
import { contentAutopilotPromptsLogic } from './contentAutopilotPromptsLogic'

export const SUGGESTION_POLL_INTERVAL_MS = 3000
export const SUGGESTION_COUNTS = [10, 20, 30, 50]

export interface PromptSuggestionForm {
    domain: string
    brand: string
    description: string
    competitors: string[]
    topics: string[]
    count: number
}

const EMPTY_FORM: PromptSuggestionForm = {
    domain: '',
    brand: '',
    description: '',
    competitors: [],
    topics: [],
    count: 20,
}

export const siteDomain = (url: string): string => url.replace(/^https?:\/\//, '').replace(/\/.*$/, '')

const startErrorMessage = (error: unknown): string =>
    error instanceof ApiError && error.status && error.status < 500 && error.detail
        ? error.detail
        : "Couldn't start the suggestions. Try again."

