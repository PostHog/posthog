export type contentAutopilotPromptSuggestionsLogicType = MakeLogicType<
    contentAutopilotPromptSuggestionsLogicValues,
    contentAutopilotPromptSuggestionsLogicActions,
    Record<string, any>,
    contentAutopilotPromptSuggestionsLogicMeta
>

export const contentAutopilotPromptSuggestionsLogic = kea<contentAutopilotPromptSuggestionsLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotPromptSuggestionsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], contentAutopilotLogic, ['profile']],
        actions: [contentAutopilotPromptsLogic, ['addPromptsSuccess']],
    })),
    actions({
        openSuggest: true,
        closeSuggest: true,
        setForm: (form: Partial<PromptSuggestionForm>) => ({ form }),
        startSuggestions: true,
        startSuggestionsFailure: (error: string) => ({ error }),
        setJob: (job: AEOPromptSuggestionJobApi) => ({ job }),
        loadJob: true,
        editRequest: true,
        toggleSuggestion: (prompt: string) => ({ prompt }),
        setSelectedPrompts: (prompts: string[]) => ({ prompts }),
        addSelected: true,
        addSelectedSuccess: true,
        addSelectedFailure: true,
    }),
    reducers({
        suggestOpen: [
            false,
            {
                openSuggest: () => true,
                closeSuggest: () => false,
                addSelectedSuccess: () => false,
            },
        ],
        form: [
            EMPTY_FORM,
            {
                setForm: (state, { form }) => ({ ...state, ...form }),
            },
        ],
        job: [
            null as AEOPromptSuggestionJobApi | null,
            {
                setJob: (_, { job }) => job,
                editRequest: () => null,
                addSelectedSuccess: () => null,
            },
        ],
        starting: [
            false,
            {
                startSuggestions: () => true,
                setJob: () => false,
                startSuggestionsFailure: () => false,
            },
        ],
        startError: [
            null as string | null,
            {
                startSuggestions: () => null,
                startSuggestionsFailure: (_, { error }) => error,
                editRequest: () => null,
            },
        ],
        selectedPrompts: [
            [] as string[],
            {
                setSelectedPrompts: (_, { prompts }) => prompts,
                toggleSuggestion: (state, { prompt }) =>
                    state.includes(prompt) ? state.filter((p) => p !== prompt) : [...state, prompt],
                editRequest: () => [],
            },
        ],
        adding: [
            false,
            {
                addSelected: () => true,
                addSelectedSuccess: () => false,
                addSelectedFailure: () => false,
            },
        ],
    }),
    selectors({
        selectedSuggestions: [
            (s) => [s.job, s.selectedPrompts],
            (job: AEOPromptSuggestionJobApi | null, selectedPrompts: string[]): AEOPromptSuggestionApi[] =>
                (job?.suggestions ?? []).filter(({ prompt }) => selectedPrompts.includes(prompt)),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openSuggest: () => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot prompt suggestions opened')
            if (!values.form.domain && values.profile) {
                actions.setForm({ domain: siteDomain(values.profile.domain), brand: values.profile.name ?? '' })
            }
        },
        startSuggestions: async () => {
            const { form } = values
            try {
                const job = await aeoPromptsSuggest(String(values.currentTeamIdStrict), {
                    domain: siteDomain(form.domain.trim()),
                    brand: form.brand.trim(),
                    description: form.description.trim(),
                    competitors: form.competitors,
                    topics: form.topics,
                    count: form.count,
                })
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics content autopilot prompt suggestions started', { count: form.count })
                actions.setJob(job)
            } catch (error) {
                actions.startSuggestionsFailure(startErrorMessage(error))
            }
        },
        setJob: ({ job }) => {
            if (job.status === 'pending') {
                cache.disposables.add(() => {
                    const id = setInterval(() => actions.loadJob(), SUGGESTION_POLL_INTERVAL_MS)
                    return () => clearInterval(id)
                }, 'suggestionPoll')
                return
            }
            cache.disposables.dispose('suggestionPoll')
            if (job.status === 'completed') {
                actions.setSelectedPrompts(job.suggestions.map(({ prompt }) => prompt))
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics content autopilot prompt suggestions completed', {
                    suggestions: job.suggestions.length,
                })
            }
        },
        loadJob: async (_, breakpoint) => {
            const jobId = values.job?.id
            if (!jobId || values.job?.status !== 'pending') {
                return
            }
            try {
                const job = await aeoPromptsSuggestionRetrieve(String(values.currentTeamIdStrict), jobId)
                breakpoint()
                // A job the user replaced with a new request must not overwrite it.
                if (job.id === values.job?.id && job.status !== 'pending') {
                    actions.setJob(job)
                }
            } catch {
                // A missed poll is retried on the next tick; an expired job shows as failed.
                if (values.job?.id === jobId) {
                    cache.pollFailures = (cache.pollFailures ?? 0) + 1
                    if (cache.pollFailures >= 5) {
                        cache.pollFailures = 0
                        actions.setJob({ ...values.job, status: 'failed', error: "Couldn't load the suggestions." })
                    }
                }
            }
        },
        editRequest: () => {
            cache.disposables.dispose('suggestionPoll')
        },
        addSelected: async () => {
            try {
                const result = await aeoPromptsBulkImport(String(values.currentTeamIdStrict), {
                    prompts: values.selectedSuggestions.map(({ prompt, topic }) => ({ prompt, topic })),
                })
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics content autopilot prompt suggestions added', {
                    added: values.selectedSuggestions.length,
                    suggested: values.job?.suggestions.length ?? 0,
                })
                actions.addSelectedSuccess()
                // Reuses the import toast, and reloads the list, topics and overview.
                actions.addPromptsSuccess(result)
            } catch {
                actions.addSelectedFailure()
                lemonToast.error("Couldn't add the prompts. Try again.")
            }
        },
    })),
])
