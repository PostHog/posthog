const overviewItems = (response: { results?: WebOverviewItem[] }): WebOverviewItem[] => response.results ?? []

export const contentAutopilotAiTrafficLogic = kea<contentAutopilotAiTrafficLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotAiTrafficLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'timezone'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        setDateRange: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setTrendMetric: (trendMetric: AiTrafficTrendMetric) => ({ trendMetric }),
        setConversionGoal: (conversionGoal: WebAnalyticsConversionGoal | null) => ({ conversionGoal }),
        setPageFilter: (pageFilter: AiTrafficPageFilter) => ({ pageFilter }),
        reload: true,
        loadSummary: true,
        loadConversion: true,
        loadPageSources: true,
    }),
    loaders(({ values }) => ({
        summary: [
            null as AiTrafficSummary | null,
            {
                loadSummary: async (_, breakpoint) => {
                    await breakpoint(100)
                    const [ai, all] = await Promise.all([
                        performQuery(aiTrafficOverviewQuery(values.filters, { aiOnly: true, conversionGoal: null })),
                        performQuery(aiTrafficOverviewQuery(values.filters, { aiOnly: false, conversionGoal: null })),
                    ])
                    breakpoint()
                    return {
                        aiVisitors: overviewValue(overviewItems(ai), 'visitors') ?? 0,
                        aiSessions: overviewValue(overviewItems(ai), 'sessions') ?? 0,
                        allSessions: overviewValue(overviewItems(all), 'sessions') ?? 0,
                    }
                },
            },
        ],
        conversion: [
            null as AiTrafficConversion | null,
            {
                loadConversion: async (_, breakpoint) => {
                    const { conversionGoal } = values
                    if (!conversionGoal) {
                        return null
                    }
                    await breakpoint(100)
                    const [ai, all] = await Promise.all([
                        performQuery(aiTrafficOverviewQuery(values.filters, { aiOnly: true, conversionGoal })),
                        performQuery(aiTrafficOverviewQuery(values.filters, { aiOnly: false, conversionGoal })),
                    ])
                    breakpoint()
                    return {
                        aiRate: overviewValue(overviewItems(ai), 'conversion rate'),
                        allRate: overviewValue(overviewItems(all), 'conversion rate'),
                        aiConversions: overviewValue(overviewItems(ai), 'unique conversions') ?? 0,
                    }
                },
            },
        ],
        pageSources: [
            null as AiTrafficPageSources | null,
            {
                loadPageSources: async (_, breakpoint) => {
                    await breakpoint(100)
                    const window = resolveAiTrafficWindow(values.filters, values.timezone)
                    const [landed, cited] = await Promise.all([
                        performQuery(aiTrafficLandedPagesQuery(values.filters)),
                        values.promptTrackingEnabled
                            ? performQuery(aiTrafficCitedPagesQuery(window))
                            : Promise.resolve(null),
                    ])
                    breakpoint()
                    return {
                        landed: parseLandedPages(landed.results),
                        cited: cited ? parseCitedPages(cited.results) : null,
                    }
                },
            },
        ],
    })),
    reducers({
        dateFrom: [AI_TRAFFIC_DEFAULT_DATE_FROM as string | null, { setDateRange: (_, { dateFrom }) => dateFrom }],
        dateTo: [null as string | null, { setDateRange: (_, { dateTo }) => dateTo }],
        trendMetric: ['visitors' as AiTrafficTrendMetric, { setTrendMetric: (_, { trendMetric }) => trendMetric }],
        conversionGoal: [
            null as WebAnalyticsConversionGoal | null,
            { setConversionGoal: (_, { conversionGoal }) => conversionGoal },
        ],
        pageFilter: ['all' as AiTrafficPageFilter, { setPageFilter: (_, { pageFilter }) => pageFilter }],
        summaryError: [false, { loadSummary: () => false, loadSummaryFailure: () => true }],
        conversionError: [false, { loadConversion: () => false, loadConversionFailure: () => true }],
        pageSourcesError: [false, { loadPageSources: () => false, loadPageSourcesFailure: () => true }],
    }),
    selectors({
        promptTrackingEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.AEO_CITATION_TRACKING],
        ],
        filters: [
            (s) => [s.dateFrom, s.dateTo, s.currentTeam],
            (
                dateFrom: string | null,
                dateTo: string | null,
                currentTeam: null | import('~/types').TeamType
            ): AiTrafficFilters => ({
                dateFrom,
                dateTo,
                filterTestAccounts: !!currentTeam?.test_account_filters_default_checked,
            }),
        ],
        trendQuery: [
            (s) => [s.filters, s.trendMetric],
            (filters: AiTrafficFilters, trendMetric: AiTrafficTrendMetric): InsightVizNode =>
                aiTrafficTrendQuery(filters, trendMetric),
        ],
        entryPagesQuery: [
            (s) => [s.filters, s.conversionGoal],
            (filters: AiTrafficFilters, conversionGoal: WebAnalyticsConversionGoal | null): DataTableNode =>
                aiTrafficEntryPagesQuery(filters, conversionGoal),
        ],
        pageRows: [
            (s) => [s.pageSources],
            (pageSources: AiTrafficPageSources | null): AiTrafficPageRow[] | null =>
                pageSources?.cited ? joinCitedAndLanded(pageSources.cited, pageSources.landed) : null,
        ],
        pageCounts: [
            (s) => [s.pageRows],
            (pageRows: AiTrafficPageRow[] | null): Record<AiTrafficPageStatus, number> | null =>
                pageRows ? countPagesByStatus(pageRows) : null,
        ],
        filteredPageRows: [
            (s) => [s.pageRows, s.pageFilter],
            (pageRows: AiTrafficPageRow[] | null, pageFilter: AiTrafficPageFilter): AiTrafficPageRow[] | null =>
                pageRows && pageFilter !== 'all' ? pageRows.filter((row) => row.status === pageFilter) : pageRows,
        ],
    }),
    listeners(({ actions }) => ({
        reload: () => {
            actions.loadSummary()
            actions.loadConversion()
            actions.loadPageSources()
        },
        setDateRange: ({ dateFrom, dateTo }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot ai traffic date range changed', {
                date_from: dateFrom,
                date_to: dateTo,
            })
            actions.reload()
        },
        setTrendMetric: ({ trendMetric }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot ai traffic metric changed', { metric: trendMetric })
        },
        setConversionGoal: ({ conversionGoal }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot ai traffic conversion goal changed', {
                goal_type: conversionGoal ? ('actionId' in conversionGoal ? 'action' : 'event') : null,
            })
            actions.loadConversion()
        },
        setPageFilter: ({ pageFilter }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot ai traffic pages filtered', { filter: pageFilter })
        },
        loadSummarySuccess: ({ summary }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot ai traffic loaded', {
                has_ai_traffic: !!summary && summary.aiSessions > 0,
            })
        },
    })),
    afterMount(({ actions }) => {
        // pinned: analytics event name, renaming it breaks dashboards
        posthog.capture('web analytics content autopilot ai traffic viewed')
        actions.reload()
    }),
])
