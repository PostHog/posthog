/** The project's prompt topics, and the rename, merge and remove edits the topics setting makes to them. */
export const aiVisibilityTopicsLogic = kea<aiVisibilityTopicsLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'aiVisibilityTopicsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
    })),
    actions({
        openTopicDialog: (kind: TopicChangeKind, topic: string) => ({ kind, topic }),
        closeTopicDialog: true,
        renameTopic: (topic: string, newTopic: string) => ({ topic, newTopic }),
        mergeTopics: (topic: string, intoTopic: string) => ({ topic, intoTopic }),
        removeTopic: (topic: string) => ({ topic }),
        topicChangeSuccess: (kind: TopicChangeKind, change: AEOPromptTopicChangeApi) => ({ kind, change }),
        topicChangeFailure: (error: string) => ({ error }),
    }),
    loaders(({ values }) => ({
        promptTopics: [
            null as AEOPromptTopicApi[] | null,
            {
                loadPromptTopics: async () => aeoPromptsTopics(String(values.currentTeamIdStrict)),
            },
        ],
    })),
    reducers({
        promptTopicsError: [
            false,
            {
                loadPromptTopics: () => false,
                loadPromptTopicsFailure: () => true,
            },
        ],
        topicDialog: [
            null as TopicDialog | null,
            {
                openTopicDialog: (_, dialog) => dialog,
                closeTopicDialog: () => null,
                topicChangeSuccess: () => null,
            },
        ],
        topicChangeSaving: [
            false,
            {
                renameTopic: () => true,
                mergeTopics: () => true,
                removeTopic: () => true,
                topicChangeSuccess: () => false,
                topicChangeFailure: () => false,
            },
        ],
        topicChangeError: [
            null as string | null,
            {
                openTopicDialog: () => null,
                renameTopic: () => null,
                mergeTopics: () => null,
                removeTopic: () => null,
                topicChangeFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        namedTopics: [
            (s) => [s.promptTopics],
            (promptTopics: AEOPromptTopicApi[] | null): AEOPromptTopicApi[] =>
                (promptTopics ?? []).filter(({ topic }) => topic !== ''),
        ],
    }),
    listeners(({ actions, values }) => {
        const change = async (
            kind: TopicChangeKind,
            request: () => Promise<AEOPromptTopicChangeApi>
        ): Promise<void> => {
            try {
                actions.topicChangeSuccess(kind, await request())
            } catch (error) {
                // The API explains a refused edit, such as a name another topic has, so the dialog shows it.
                const refused = error instanceof ApiError && [400, 404, 409].includes(error.status ?? 0)
                actions.topicChangeFailure((refused && error.detail) || CHANGE_FAILED[kind])
            }
        }
        const teamId = (): string => String(values.currentTeamIdStrict)
        return {
            renameTopic: ({ topic, newTopic }) =>
                change('rename', () => aeoPromptsTopicsRename(teamId(), { topic, new_topic: newTopic })),
            mergeTopics: ({ topic, intoTopic }) =>
                change('merge', () => aeoPromptsTopicsMerge(teamId(), { topic, into_topic: intoTopic })),
            removeTopic: ({ topic }) => change('remove', () => aeoPromptsTopicsRemove(teamId(), { topic })),
            topicChangeSuccess: ({ kind, change }) => {
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics ai visibility topic changed', { kind, prompts: change.prompts })
                lemonToast.success(topicChangeMessage(kind, change))
                actions.loadPromptTopics()
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadPromptTopics()
    }),
])
