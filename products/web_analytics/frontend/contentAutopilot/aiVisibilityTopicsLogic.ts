import {
    aeoPromptsTopics,
    aeoPromptsTopicsMerge,
    aeoPromptsTopicsRemove,
    aeoPromptsTopicsRename,
} from 'products/web_analytics/frontend/generated/api'
import type { AEOPromptTopicApi, AEOPromptTopicChangeApi } from 'products/web_analytics/frontend/generated/api.schemas'

export type TopicChangeKind = 'rename' | 'merge' | 'remove'

export interface TopicDialog {
    kind: TopicChangeKind
    topic: string
}

const CHANGE_FAILED: Record<TopicChangeKind, string> = {
    rename: "Couldn't rename the topic. Try again.",
    merge: "Couldn't merge the topics. Try again.",
    remove: "Couldn't remove the topic. Try again.",
}

export const topicChangeMessage = (kind: TopicChangeKind, change: AEOPromptTopicChangeApi): string => {
    const prompts = pluralize(change.prompts, 'prompt')
    return kind === 'rename'
        ? `Renamed the topic on ${prompts}.`
        : kind === 'merge'
          ? `Moved ${prompts} to the other topic.`
          : `Removed the topic from ${prompts}.`
}

