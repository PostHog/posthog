const MAX_POLL_FAILURES = 5
// The server marks a lost job failed after 20 minutes; this is the fallback if that answer never arrives.
const CLIENT_JOB_DEADLINE_MS = 22 * 60 * 1000
const STOPPED_JOB_ERROR = 'Setup stopped before it finished. Try again.'
const POLL_ERROR = "Couldn't check on setup. Try again, or dismiss this and check the Prompts tab."
// While the first checks run, the overview reloads on this cadence until results arrive, for at most this long.
const FIRST_CHECKS_POLL_MS = 20 * 1000
const FIRST_CHECKS_POLL_LIMIT_MS = 30 * 60 * 1000

export interface SetupJobRef {
    id: string
    teamId: number | string
    onlyFirstRun: boolean
    startedAt: number
}

const startErrorMessage = (error: unknown): string =>
    error instanceof ApiError && error.status && error.status < 500 && error.detail
        ? error.detail
        : "Couldn't start setup. Try again."

const runningJobId = (error: unknown): string | null =>
    error instanceof ApiError && error.status === 409 && typeof error.data?.job_id === 'string'
        ? error.data.job_id
        : null

export const websiteSourceHint = (source: AEOWebsiteCandidateApi['source'], days: number): string =>
    ({
        own_brand: 'Your brand in AI visibility settings.',
        app_urls: "From your project's authorized URLs.",
        recording_domains: 'From the domains allowed to record sessions.',
        pageviews: `The site with the most pageviews in the last ${days} days.`,
    })[source]

export const defaultEngines = (engines: AEOEngineSettingApi[]): string[] =>
    engines.filter((engine) => engine.enabled && engine.available).map(({ engine }) => engine)

const stepOf = (job: AEOSetupJobApi | null, step: AEOSetupStepApi['step']): AEOSetupStepApi | null =>
    job?.steps.find((item) => item.step === step) ?? null

