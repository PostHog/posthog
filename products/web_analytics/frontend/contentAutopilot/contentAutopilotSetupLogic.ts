import { contentAutopilotPromptsOverviewLogic } from './contentAutopilotPromptsOverviewLogic'
import { SUGGESTION_POLL_INTERVAL_MS } from './contentAutopilotPromptSuggestionsLogic'

const MAX_POLL_FAILURES = 5
// The server marks a lost job failed after 16 minutes; this is the fallback if that answer never arrives.
const CLIENT_JOB_DEADLINE_MS = 18 * 60 * 1000
const STOPPED_JOB_ERROR = 'Setup stopped before it finished. Try again.'

export interface SetupJobRef {
    id: string
    teamId: number | string
    runFirstCheck: boolean
    startedAt: number
}

const startErrorMessage = (error: unknown): string =>
    error instanceof ApiError && error.status && error.status < 500 && error.detail
        ? error.detail
        : "Couldn't start setup. Try again."

export const WEBSITE_SOURCE_HINTS: Record<AEOWebsiteCandidateApi['source'], string> = {
    own_brand: 'Your brand in AI visibility settings.',
    app_urls: "From your project's authorized URLs.",
    recording_domains: 'From the domains allowed to record sessions.',
    pageviews: 'The site with the most pageviews in the last 7 days.',
}

export const defaultEngines = (engines: AEOEngineSettingApi[]): string[] =>
    engines.filter((engine) => engine.enabled && engine.available).map(({ engine }) => engine)

