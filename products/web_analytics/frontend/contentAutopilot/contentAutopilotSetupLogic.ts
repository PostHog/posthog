export const contentAutopilotSetupLogic = kea<contentAutopilotSetupLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotSetupLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
    })),
    actions({
        setDomain: (domain: string) => ({ domain }),
        toggleEngine: (engine: string, enabled: boolean) => ({ engine, enabled }),
        startSetup: (runFirstCheck: boolean) => ({ runFirstCheck }),
        startFirstRun: (activatePaused: boolean) => ({ activatePaused }),
        startSetupFailure: (error: string) => ({ error }),
        followJob: (jobRef: SetupJobRef) => ({ jobRef }),
        setJobRef: (jobRef: SetupJobRef | null) => ({ jobRef }),
        setJob: (job: AEOSetupJobApi | null) => ({ job }),
        setPollError: (error: string | null) => ({ error }),
        resumeJob: true,
        retryJob: true,
        loadJob: true,
        dismissJob: true,
        watchFirstChecks: true,
    }),
    loaders(({ values }) => ({
        setupContext: [
            null as AEOSetupContextApi | null,
            {
                loadSetupContext: async () => await aeoSetupContext(String(values.currentTeamIdStrict)),
            },
        ],
    })),
    reducers({
        // null until the person edits it, so the field shows the best candidate once the context loads.
        domainInput: [null as string | null, { setDomain: (_, { domain }) => domain }],
        engineChoices: [
            null as string[] | null,
            {
                toggleEngine: (state, { engine, enabled }) => {
                    const current = state ?? []
                    return enabled
                        ? [...current.filter((e) => e !== engine), engine]
                        : current.filter((e) => e !== engine)
                },
                loadSetupContextSuccess: (state, { setupContext }) =>
                    state ?? (setupContext ? defaultEngines(setupContext.engines) : null),
            },
        ],
        setupContextError: [
            false,
            {
                loadSetupContext: () => false,
                loadSetupContextFailure: () => true,
                loadSetupContextSuccess: () => false,
            },
        ],
        starting: [
            false,
            {
                startSetup: () => true,
                startFirstRun: () => true,
                setJob: () => false,
                followJob: () => false,
                startSetupFailure: () => false,
            },
        ],
        startError: [
            null as string | null,
            { startSetup: () => null, startFirstRun: () => null, startSetupFailure: (_, { error }) => error },
        ],
        pollError: [
            null as string | null,
            { setPollError: (_, { error }) => error, setJob: () => null, retryJob: () => null, dismissJob: () => null },
        ],
        job: [null as AEOSetupJobApi | null, { setJob: (_, { job }) => job, dismissJob: () => null }],
        jobRef: [
            null as SetupJobRef | null,
            { persist: true },
            { setJobRef: (_, { jobRef }) => jobRef, followJob: (_, { jobRef }) => jobRef, dismissJob: () => null },
        ],
    }),
    selectors({
        bestWebsite: [
            (s) => [s.setupContext],
            (context: AEOSetupContextApi | null): AEOWebsiteCandidateApi | null => context?.websites[0] ?? null,
        ],
        domain: [
            (s) => [s.domainInput, s.bestWebsite],
            (input: string | null, best: AEOWebsiteCandidateApi | null): string => input ?? best?.domain ?? '',
        ],
        websiteHint: [
            (s) => [s.domainInput, s.bestWebsite, s.setupContext],
            (
                input: string | null,
                best: AEOWebsiteCandidateApi | null,
                context: AEOSetupContextApi | null
            ): string | null =>
                best && context && (input === null || input === best.domain)
                    ? websiteSourceHint(best.source, context.website_days)
                    : null,
        ],
        selectedEngines: [
            (s) => [s.engineChoices, s.setupContext],
            (choices: string[] | null, context: AEOSetupContextApi | null): string[] =>
                (choices ?? []).filter((engine) =>
                    context?.engines.some((setting) => setting.engine === engine && setting.available)
                ),
        ],
        activeEngineCount: [
            (s) => [s.setupContext],
            (context: AEOSetupContextApi | null): number => (context ? defaultEngines(context.engines).length : 0),
        ],
        consentMissing: [
            (s) => [s.setupContext],
            (context: AEOSetupContextApi | null): boolean => !!context && !context.ai_data_processing_approved,
        ],
        startDisabledReason: [
            (s) => [s.domain, s.selectedEngines, s.setupContext, s.starting],
            (
                domain: string,
                engines: string[],
                context: AEOSetupContextApi | null,
                starting: boolean
            ): string | undefined =>
                !context
                    ? 'Loading…'
                    : !context.ai_data_processing_approved
                      ? 'Needs AI data processing approved for your organization'
                      : starting
                        ? 'Starting…'
                        : !domain.trim()
                          ? 'Enter your site'
                          : engines.length === 0
                            ? 'Choose at least one engine'
                            : undefined,
        ],
        firstRunDisabledReason: [
            (s) => [s.setupContext, s.activeEngineCount, s.starting],
            (context: AEOSetupContextApi | null, engines: number, starting: boolean): string | undefined =>
                !context
                    ? 'Loading…'
                    : !context.first_run_available
                      ? "Checks aren't available for this project yet"
                      : engines === 0
                        ? 'Turn on an engine in settings first'
                        : starting
                          ? 'Starting…'
                          : undefined,
        ],
        jobRunning: [(s) => [s.job], (job: AEOSetupJobApi | null): boolean => job?.status === 'pending'],
        /** A full setup job, as opposed to a run started from the first-run card. */
        setupJobShown: [
            (s) => [s.job, s.jobRef],
            (job: AEOSetupJobApi | null, jobRef: SetupJobRef | null): boolean => !!job && !jobRef?.onlyFirstRun,
        ],
        firstRunStep: [(s) => [s.job], (job: AEOSetupJobApi | null) => stepOf(job, 'first_run')],
        firstRunQueued: [(s) => [s.firstRunStep], (step: AEOSetupStepApi | null): boolean => step?.status === 'done'],
    }),
    listeners(({ actions, values, cache }) => ({
        startSetup: async ({ runFirstCheck }) => {
            try {
                const job = await aeoSetupCreate(String(values.currentTeamIdStrict), {
                    domain: values.domain.trim(),
                    engines: values.selectedEngines,
                    run_first_check: runFirstCheck,
                })
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics ai visibility setup started', {
                    run_first_check: runFirstCheck,
                    engines: values.selectedEngines.length,
                    website_source: values.websiteHint ? values.bestWebsite?.source : 'typed',
                })
                cache.pollFailures = 0
                actions.setJobRef({
                    id: job.id,
                    teamId: values.currentTeamIdStrict,
                    onlyFirstRun: false,
                    startedAt: Date.now(),
                })
                actions.setJob(job)
            } catch (error) {
                const running = runningJobId(error)
                if (running) {
                    actions.followJob({
                        id: running,
                        teamId: values.currentTeamIdStrict,
                        onlyFirstRun: false,
                        startedAt: Date.now(),
                    })
                    return
                }
                actions.startSetupFailure(startErrorMessage(error))
            }
        },
        startFirstRun: async ({ activatePaused }) => {
            try {
                const job = await aeoSetupCreate(String(values.currentTeamIdStrict), {
                    only_first_run: true,
                    activate_paused_prompts: activatePaused,
                })
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics ai visibility first run started', { activate_paused: activatePaused })
                cache.pollFailures = 0
                actions.setJobRef({
                    id: job.id,
                    teamId: values.currentTeamIdStrict,
                    onlyFirstRun: true,
                    startedAt: Date.now(),
                })
                actions.setJob(job)
            } catch (error) {
                const running = runningJobId(error)
                if (running) {
                    actions.followJob({
                        id: running,
                        teamId: values.currentTeamIdStrict,
                        onlyFirstRun: true,
                        startedAt: Date.now(),
                    })
                    return
                }
                actions.startSetupFailure(startErrorMessage(error))
            }
        },
        followJob: () => {
            // Another tab or person started setup first, so this page follows that job instead.
            cache.pollFailures = 0
            actions.loadJob()
            actions.resumeJob()
        },
        setJob: ({ job }) => {
            if (!job) {
                return
            }
            if (job.status === 'pending') {
                cache.pollingJobId = job.id
                actions.resumeJob()
                return
            }
            cache.disposables.dispose('setupPoll')
            if (cache.pollingJobId !== job.id) {
                return
            }
            cache.pollingJobId = null
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics ai visibility setup finished', { status: job.status })
            // The overview and the keyword list read what setup saved.
            contentAutopilotPromptsOverviewLogic.findMounted()?.actions.loadPromptSetOverview()
            contentAutopilotKeywordsLogic.findMounted()?.actions.loadKeywords()
            if (values.firstRunQueued) {
                actions.watchFirstChecks()
            }
            // Paused prompts are not in the overview's count, so the context tells the overview they exist.
            if (stepOf(job, 'prompts')?.detail === 'paused' || values.jobRef?.onlyFirstRun) {
                actions.loadSetupContext()
            }
        },
        watchFirstChecks: () => {
            const until = Date.now() + FIRST_CHECKS_POLL_LIMIT_MS
            cache.disposables.add(() => {
                const id = setInterval(() => {
                    const overview = contentAutopilotPromptsOverviewLogic.findMounted()
                    if (!overview || overview.values.hasChecks || Date.now() > until) {
                        cache.disposables.dispose('firstChecksPoll')
                        return
                    }
                    overview.actions.loadPromptSetOverview()
                }, FIRST_CHECKS_POLL_MS)
                return () => clearInterval(id)
            }, 'firstChecksPoll')
        },
        resumeJob: () => {
            cache.disposables.add(() => {
                const id = setInterval(() => actions.loadJob(), SUGGESTION_POLL_INTERVAL_MS)
                return () => clearInterval(id)
            }, 'setupPoll')
        },
        retryJob: () => {
            cache.pollFailures = 0
            actions.loadJob()
            actions.resumeJob()
        },
        dismissJob: () => {
            cache.disposables.dispose('setupPoll')
            cache.pollingJobId = null
        },
        loadJob: async () => {
            const jobRef = values.jobRef
            // Polls never overlap, so a slow response cannot be overtaken and miscounted as a failure.
            if (!jobRef || cache.pollInFlight) {
                return
            }
            cache.pollInFlight = true
            try {
                const fetched = await aeoSetupRetrieve(String(values.currentTeamIdStrict), jobRef.id)
                cache.pollFailures = 0
                const job: AEOSetupJobApi =
                    fetched.status === 'pending' && Date.now() - jobRef.startedAt > CLIENT_JOB_DEADLINE_MS
                        ? { ...fetched, status: 'failed', error: STOPPED_JOB_ERROR }
                        : fetched
                if (!cache.disposables.isDisposed && job.id === values.jobRef?.id) {
                    if (cache.pollingJobId !== job.id && job.status === 'pending') {
                        cache.pollingJobId = job.id
                    }
                    actions.setJob(job)
                }
            } catch (error) {
                cache.pollFailures = (cache.pollFailures ?? 0) + 1
                if (error instanceof ApiError && error.status === 404) {
                    // A job the cache no longer holds is gone for good, so it stops being restored.
                    cache.disposables.dispose('setupPoll')
                    actions.dismissJob()
                } else if (cache.pollFailures >= MAX_POLL_FAILURES) {
                    cache.disposables.dispose('setupPoll')
                    actions.setPollError(POLL_ERROR)
                }
            } finally {
                cache.pollInFlight = false
            }
        },
    })),
    afterMount(({ actions, values }) => {
        actions.loadSetupContext()
        // A job started before a reload keeps reporting here. One from another project is dropped.
        if (values.jobRef && values.jobRef.teamId !== values.currentTeamIdStrict) {
            actions.setJobRef(null)
        } else if (values.jobRef) {
            actions.loadJob()
            actions.resumeJob()
        }
    }),
])
