import {
    LogicWrapper,
    MakeLogicType,
    actions,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
    selectors,
} from 'kea'
import posthog from 'posthog-js'

import { ApiError } from 'lib/api-error'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import type { BrandKindEnumApi } from 'products/web_analytics/frontend/generated/api.schemas'

import { aiVisibilityBrandsLogic } from './aiVisibilityBrandsLogic'
import { bareDomain, saveBrand } from './brandCatalog'
import { contentAutopilotSetupLogic } from './contentAutopilotSetupLogic'

export type AddableBrandKind = Extract<BrandKindEnumApi, 'own' | 'competitor'>

export interface AiVisibilityAddBrandLogicProps {
    formKey: string
    defaultKind: AddableBrandKind
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiVisibilityAddBrandLogicValues {
    currentTeamIdStrict: number | string // teamLogic
    adding: boolean
    disabledReason: string | undefined
    domain: string
    error: string | null
    kind: AddableBrandKind
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiVisibilityAddBrandLogicActions {
    addBrand: () => {
        value: true
    }
    addBrandFailure: (error: string) => {
        error: string
    }
    addBrandSuccess: () => {
        value: true
    }
    setDomain: (domain: string) => {
        domain: string
    }
    setKind: (kind: AddableBrandKind) => {
        kind: AddableBrandKind
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiVisibilityAddBrandLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        disabledReason: (domain: string, adding: boolean) => string | undefined
    }
}

export type aiVisibilityAddBrandLogicType = MakeLogicType<
    aiVisibilityAddBrandLogicValues,
    aiVisibilityAddBrandLogicActions,
    AiVisibilityAddBrandLogicProps,
    aiVisibilityAddBrandLogicMeta
>

const failureMessage = (error: unknown): string =>
    error instanceof ApiError && error.status && error.status < 500 && error.detail
        ? error.detail
        : "Couldn't add the brand. Try again."

export const aiVisibilityAddBrandLogic: LogicWrapper<aiVisibilityAddBrandLogicType> =
    kea<aiVisibilityAddBrandLogicType>([
        props({} as AiVisibilityAddBrandLogicProps),
        key((props) => props.formKey),
        path((key) => ['products', 'webAnalytics', 'contentAutopilot', 'aiVisibilityAddBrandLogic', key]),
        connect(() => ({ values: [teamLogic, ['currentTeamIdStrict']] })),
        actions({
            setDomain: (domain: string) => ({ domain }),
            setKind: (kind: AddableBrandKind) => ({ kind }),
            addBrand: true,
            addBrandSuccess: true,
            addBrandFailure: (error: string) => ({ error }),
        }),
        reducers(({ props }) => ({
            domain: ['', { setDomain: (_, { domain }) => domain, addBrandSuccess: () => '' }],
            kind: [props.defaultKind as AddableBrandKind, { setKind: (_, { kind }) => kind }],
            adding: [false, { addBrand: () => true, addBrandSuccess: () => false, addBrandFailure: () => false }],
            error: [
                null as string | null,
                { setDomain: () => null, addBrand: () => null, addBrandFailure: (_, { error }) => error },
            ],
        })),
        selectors({
            disabledReason: [
                (s) => [s.domain, s.adding],
                (domain: string, adding: boolean): string | undefined =>
                    adding ? 'Adding…' : !bareDomain(domain) ? 'Enter a domain' : undefined,
            ],
        }),
        listeners(({ actions, values }) => ({
            addBrand: async () => {
                const teamId = String(values.currentTeamIdStrict)
                const domain = bareDomain(values.domain)
                try {
                    await saveBrand(teamId, domain, values.kind)
                } catch (error) {
                    actions.addBrandFailure(failureMessage(error))
                    return
                }
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics ai visibility brand added', { kind: values.kind })
                lemonToast.success(values.kind === 'own' ? `${domain} is set as your brand` : `Added ${domain}`)
                actions.addBrandSuccess()
                aiVisibilityBrandsLogic.findMounted()?.actions.loadBrands()
                contentAutopilotSetupLogic.findMounted()?.actions.loadSetupContext()
            },
        })),
    ])
