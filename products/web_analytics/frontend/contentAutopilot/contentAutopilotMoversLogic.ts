export type contentAutopilotMoversLogicType = MakeLogicType<
    contentAutopilotMoversLogicValues,
    contentAutopilotMoversLogicActions
>

export const contentAutopilotMoversLogic = kea<contentAutopilotMoversLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotMoversLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], contentAutopilotFiltersLogic, ['filters']],
        actions: [
            contentAutopilotFiltersLogic,
            ['setDates', 'setEngine', 'setTopic', 'setBrandedSegment', 'applyUrlFilters'],
            contentAutopilotLogic,
            ['setWorkspaceTab'],
            contentAutopilotPromptDetailLogic,
            ['openPromptDetail'],
        ],
    })),
    actions({
        loadMovers: true,
        openMoverPrompt: (promptId: string, direction: 'gained' | 'lost') => ({ promptId, direction }),
    }),
    loaders(({ values }) => ({
        movers: [
            null as AEOPromptSetMoversApi | null,
            {
                loadMovers: async (_, breakpoint) => {
                    try {
                        const movers = await aeoPromptsMovers(
                            String(values.currentTeamIdStrict),
                            filtersToQueryParams(values.filters)
                        )
                        breakpoint()
                        return movers
                    } catch (error) {
                        // A superseded request's failure must not replace newer movers with an error
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        moversError: [
            null as ContentAutopilotPromptsError | null,
            {
                loadMovers: () => null,
                loadMoversFailure: (_, { errorObject }) => promptsErrorFrom(errorObject),
            },
        ],
    }),
    listeners(({ actions }) => ({
        openMoverPrompt: ({ promptId, direction }) => {
            posthog.capture('web analytics content autopilot prompts overview mover prompt opened', { direction })
            actions.setWorkspaceTab('prompts')
            actions.openPromptDetail(promptId)
        },
        setDates: () => actions.loadMovers(),
        setEngine: () => actions.loadMovers(),
        setTopic: () => actions.loadMovers(),
        setBrandedSegment: () => actions.loadMovers(),
        applyUrlFilters: () => actions.loadMovers(),
    })),
    afterMount(({ actions }) => {
        actions.loadMovers()
    }),
])
