export const COMPETITOR_CANDIDATE_LIMIT = 20
const CANDIDATE_RETRY_MS = 30 * 1000
const CANDIDATE_RETRY_LIMIT_MS = 30 * 60 * 1000

export type CompetitorDecision = 'confirmed' | 'rejected'

export const reviewCandidates = (
    named: AEOCompetitorCandidateApi[],
    suggested: AEOBrandApi[]
): Pick<CompetitorReview, 'candidates' | 'suggestedIds'> => {
    const suggestedIds = suggested
        .map((brand) => brand.id)
        .filter((id) => named.some((candidate) => candidate.brand_id === id))
    const candidates = [...named].sort(
        (a, b) => Number(suggestedIds.includes(b.brand_id)) - Number(suggestedIds.includes(a.brand_id))
    )
    return { candidates, suggestedIds }
}

export interface CompetitorReview {
    candidates: AEOCompetitorCandidateApi[]
    suggestedIds: string[]
    /** Whether the project had a confirmed competitor when the review loaded. */
    alreadyConfirmed: boolean
}

