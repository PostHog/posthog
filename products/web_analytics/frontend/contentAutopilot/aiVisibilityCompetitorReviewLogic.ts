export type aiVisibilityCompetitorReviewLogicType = MakeLogicType<
    aiVisibilityCompetitorReviewLogicValues,
    aiVisibilityCompetitorReviewLogicActions,
    Record<string, any>,
    aiVisibilityCompetitorReviewLogicMeta
>

export const aiVisibilityCompetitorReviewLogic = kea<aiVisibilityCompetitorReviewLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'aiVisibilityCompetitorReviewLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
    })),
    actions({
        reviewCandidate: (brandId: string, decision: CompetitorDecision) => ({ brandId, decision }),
        reviewCandidateSuccess: (brandId: string, decision: CompetitorDecision) => ({ brandId, decision }),
        reviewCandidateFailure: (brandId: string) => ({ brandId }),
        finishReview: true,
        setReviewFinished: (teamId: string) => ({ teamId }),
    }),
    loaders(({ values }) => ({
        review: [
            null as CompetitorReview | null,
            {
                loadReview: async (): Promise<CompetitorReview | null> => {
                    const teamId = String(values.currentTeamIdStrict)
                    // Candidates come from an uncached scan of stored answers, so a project past this step skips it.
                    if (values.finishedTeamIds.includes(teamId)) {
                        return null
                    }
                    const confirmed = await aeoBrandsList(teamId, { kind: 'competitor', status: 'confirmed', limit: 1 })
                    if (confirmed.count > 0) {
                        return { candidates: [], alreadyConfirmed: true }
                    }
                    const candidates = await aeoBrandsCompetitorCandidates(teamId, {
                        limit: COMPETITOR_CANDIDATE_LIMIT,
                    })
                    return { candidates, alreadyConfirmed: false }
                },
            },
        ],
    })),
    reducers({
        review: {
            reviewCandidateSuccess: (state, { brandId }) =>
                state
                    ? { ...state, candidates: state.candidates.filter((candidate) => candidate.brand_id !== brandId) }
                    : state,
        },
        updatingIds: [
            [] as string[],
            {
                reviewCandidate: (state, { brandId }) => [...state, brandId],
                reviewCandidateSuccess: (state, { brandId }) => state.filter((id) => id !== brandId),
                reviewCandidateFailure: (state, { brandId }) => state.filter((id) => id !== brandId),
            },
        ],
        decisions: [
            { confirmed: 0, rejected: 0 } as Record<CompetitorDecision, number>,
            {
                reviewCandidateSuccess: (state, { decision }) => ({ ...state, [decision]: state[decision] + 1 }),
            },
        ],
        finishedTeamIds: [
            [] as string[],
            { persist: true },
            {
                setReviewFinished: (state, { teamId }) => (state.includes(teamId) ? state : [...state, teamId]),
            },
        ],
    }),
    selectors({
        candidates: [
            (s) => [s.review],
            (review: CompetitorReview | null): AEOCompetitorCandidateApi[] => review?.candidates ?? [],
        ],
        reviewShown: [
            (s) => [s.review, s.decisions, s.finishedTeamIds, s.currentTeamIdStrict],
            (
                review: CompetitorReview | null,
                decisions: Record<CompetitorDecision, number>,
                finishedTeamIds: string[],
                teamId: number | string
            ): boolean => {
                if (!review || review.alreadyConfirmed || finishedTeamIds.includes(String(teamId))) {
                    return false
                }
                // The step stays up after the last suggestion is reviewed, until the person closes it.
                return review.candidates.length > 0 || decisions.confirmed + decisions.rejected > 0
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadReviewSuccess: ({ review }) => {
            if (values.reviewShown) {
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics ai visibility competitor review shown', {
                    candidates: values.candidates.length,
                })
            }
            // Brands reach the catalog only when a run finishes, so a review loaded after the first run's
            // early checks finds none until the rest of that run lands.
            const firstRunQueued = contentAutopilotSetupLogic.findMounted()?.values.firstRunQueued
            if (!review || review.alreadyConfirmed || review.candidates.length > 0 || !firstRunQueued) {
                return
            }
            cache.retryUntil ??= Date.now() + CANDIDATE_RETRY_LIMIT_MS
            if (Date.now() < cache.retryUntil) {
                cache.disposables.add(() => {
                    const id = setTimeout(() => actions.loadReview(), CANDIDATE_RETRY_MS)
                    return () => clearTimeout(id)
                }, 'candidateRetry')
            }
        },
        reviewCandidate: async ({ brandId, decision }) => {
            try {
                await aeoBrandsPartialUpdate(
                    String(values.currentTeamIdStrict),
                    brandId,
                    decision === 'confirmed' ? { kind: 'competitor', status: 'confirmed' } : { status: 'ignored' }
                )
            } catch {
                lemonToast.error("Couldn't save your choice. Try again.")
                actions.reviewCandidateFailure(brandId)
                return
            }
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics ai visibility competitor candidate reviewed', { decision })
            actions.reviewCandidateSuccess(brandId, decision)
        },
        finishReview: () => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics ai visibility competitor review finished', {
                ...values.decisions,
                remaining: values.candidates.length,
            })
            actions.setReviewFinished(String(values.currentTeamIdStrict))
        },
    })),
    afterMount(({ actions }) => {
        actions.loadReview()
    }),
])
