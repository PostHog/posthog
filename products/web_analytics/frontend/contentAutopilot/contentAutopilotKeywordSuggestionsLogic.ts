export const contentAutopilotKeywordSuggestionsLogic = kea<contentAutopilotKeywordSuggestionsLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotKeywordSuggestionsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], contentAutopilotLogic, ['profile']],
        actions: [contentAutopilotKeywordsLogic, ['addKeywordsSuccess']],
    })),
    actions({
        openSuggest: true,
        closeSuggest: true,
        setForm: (form: Partial<KeywordSuggestionForm>) => ({ form }),
        startSuggestions: true,
        startSuggestionsFailure: (error: string) => ({ error }),
        setJobRef: (jobRef: KeywordSuggestionJobRef | null) => ({ jobRef }),
        setJob: (job: AEOKeywordSuggestionJobApi) => ({ job }),
        loadJob: true,
        editRequest: true,
        backToSuggestions: true,
        resumeJob: true,
        toggleSuggestion: (keyword: string) => ({ keyword }),
        setSelectedKeywords: (keywords: string[]) => ({ keywords }),
        addSelected: true,
        addSelectedSuccess: true,
        addSelectedFailure: true,
    }),
    reducers({
        suggestOpen: [
            false,
            {
                openSuggest: () => true,
                closeSuggest: () => false,
                addSelectedSuccess: () => false,
            },
        ],
        form: [
            EMPTY_FORM,
            {
                setForm: (state, { form }) => ({ ...state, ...form }),
            },
        ],
        // Only a reference to the job is kept, so a job started before leaving the page can be read again.
        jobRef: [
            null as KeywordSuggestionJobRef | null,
            { persist: true },
            {
                setJobRef: (_, { jobRef }) => jobRef,
                addSelectedSuccess: () => null,
            },
        ],
        job: [
            null as AEOKeywordSuggestionJobApi | null,
            {
                setJob: (_, { job }) => job,
                addSelectedSuccess: () => null,
            },
        ],
        // Editing the inputs keeps the current suggestions until a new request replaces them.
        editingInputs: [
            false,
            {
                editRequest: () => true,
                backToSuggestions: () => false,
                setJobRef: () => false,
                addSelectedSuccess: () => false,
            },
        ],
        starting: [
            false,
            {
                startSuggestions: () => true,
                setJob: () => false,
                startSuggestionsFailure: () => false,
            },
        ],
        startError: [
            null as string | null,
            {
                startSuggestions: () => null,
                startSuggestionsFailure: (_, { error }) => error,
                backToSuggestions: () => null,
            },
        ],
        selectedKeywords: [
            [] as string[],
            {
                setSelectedKeywords: (_, { keywords }) => keywords,
                toggleSuggestion: (state, { keyword }) =>
                    state.includes(keyword) ? state.filter((k) => k !== keyword) : [...state, keyword],
                startSuggestions: () => [],
                addSelectedSuccess: () => [],
            },
        ],
        adding: [
            false,
            {
                addSelected: () => true,
                addSelectedSuccess: () => false,
                addSelectedFailure: () => false,
            },
        ],
    }),
    selectors({
        selectedSuggestions: [
            (s) => [s.job, s.selectedKeywords],
            (job: AEOKeywordSuggestionJobApi | null, selectedKeywords: string[]): AEOKeywordSuggestionApi[] =>
                (job?.suggestions ?? []).filter(({ keyword }) => selectedKeywords.includes(keyword)),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openSuggest: () => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot keyword suggestions opened')
            if (!values.form.domain && values.profile) {
                actions.setForm({ domain: siteDomain(values.profile.domain), brand: values.profile.name ?? '' })
            }
        },
        startSuggestions: async () => {
            const { form } = values
            const domain = siteDomain(form.domain)
            try {
                const job = await aeoKeywordsSuggest(String(values.currentTeamIdStrict), {
                    domain,
                    brand: form.brand.trim(),
                    description: form.description.trim(),
                    count: form.count,
                })
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics content autopilot keyword suggestions started', { count: form.count })
                cache.pollFailures = 0
                actions.setJobRef({ id: job.id, teamId: values.currentTeamIdStrict, domain, startedAt: Date.now() })
                actions.setJob(job)
            } catch (error) {
                actions.startSuggestionsFailure(startErrorMessage(error))
            }
        },
        setJob: ({ job }) => {
            if (job.status === 'pending') {
                cache.pollingJobId = job.id
                actions.resumeJob()
                return
            }
            cache.disposables.dispose('keywordSuggestionPoll')
            // A failed or expired job has nothing left to read, so it must not be polled again after a reload.
            if (job.status === 'failed' && values.jobRef?.id === job.id) {
                actions.setJobRef(null)
            }
            if (job.status === 'completed' && values.selectedKeywords.length === 0) {
                actions.setSelectedKeywords(job.suggestions.map(({ keyword }) => keyword))
            }
            // Only a job this page watched finish counts, so restoring a finished job reports nothing.
            if (cache.pollingJobId !== job.id) {
                return
            }
            cache.pollingJobId = null
            if (job.status === 'completed') {
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics content autopilot keyword suggestions completed', {
                    suggestions: job.suggestions.length,
                })
            }
            // With the dialog closed, the result would otherwise go unnoticed.
            if (!values.suggestOpen) {
                if (job.status === 'completed') {
                    lemonToast.success(
                        job.suggestions.length
                            ? `${job.suggestions.length} keyword suggestions are ready.`
                            : 'Keyword suggestions finished with no new keywords.',
                        { button: { label: 'Review', action: () => actions.openSuggest() } }
                    )
                } else {
                    lemonToast.error(job.error || "Couldn't suggest keywords. Try again.")
                }
            }
        },
        resumeJob: () => {
            cache.disposables.add(() => {
                const id = setInterval(() => actions.loadJob(), SUGGESTION_POLL_INTERVAL_MS)
                return () => clearInterval(id)
            }, 'keywordSuggestionPoll')
        },
        loadJob: async () => {
            const jobRef = values.jobRef
            const jobId = jobRef?.id
            // Polls never overlap, so a slow response cannot be overtaken and miscounted as a failure.
            if (!jobRef || !jobId || cache.pollInFlight) {
                return
            }
            cache.pollInFlight = true
            try {
                const fetched = await aeoKeywordsSuggestionRetrieve(String(values.currentTeamIdStrict), jobId)
                cache.pollFailures = 0
                const job: AEOKeywordSuggestionJobApi =
                    fetched.status === 'pending' && Date.now() - jobRef.startedAt > CLIENT_JOB_DEADLINE_MS
                        ? { ...fetched, status: 'failed', error: STOPPED_JOB_ERROR }
                        : fetched
                // A job the user replaced with a new request must not overwrite it.
                if (
                    !cache.disposables.isDisposed &&
                    job.id === values.jobRef?.id &&
                    job.status !== values.job?.status
                ) {
                    actions.setJob(job)
                }
            } catch (error) {
                if (cache.disposables.isDisposed || values.jobRef?.id !== jobId) {
                    return
                }
                const expired = error instanceof ApiError && error.status === 404
                cache.pollFailures = (cache.pollFailures ?? 0) + 1
                if (expired || cache.pollFailures >= MAX_POLL_FAILURES) {
                    cache.pollFailures = 0
                    actions.setJob({
                        id: jobId,
                        status: 'failed',
                        suggestions: [],
                        error: expired
                            ? 'These suggestions expired. Start again to get new ones.'
                            : "Couldn't load the suggestions.",
                    })
                }
            } finally {
                cache.pollInFlight = false
            }
        },
        addSelected: async () => {
            const selected = values.selectedSuggestions
            const suggested = values.job?.suggestions.length ?? 0
            let result: AEOKeywordCreateResultApi
            try {
                result = await aeoKeywordsCreate(String(values.currentTeamIdStrict), {
                    keywords: selected.map(({ keyword }) => keyword),
                })
            } catch (error) {
                if (!cache.disposables.isDisposed) {
                    actions.addSelectedFailure()
                    // A 400 says why the keywords were refused, such as the cap, so show it rather than asking for a retry.
                    const detail = error instanceof ApiError && error.status === 400 ? error.detail : null
                    lemonToast.error(detail || "Couldn't add the keywords. Try again.")
                }
                return
            }
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot keyword suggestions added', {
                added: selected.length,
                suggested,
            })
            if (!cache.disposables.isDisposed) {
                actions.addSelectedSuccess()
                // Reuses the add toast, and reloads the list and the report.
                actions.addKeywordsSuccess(result)
            }
        },
    })),
    afterMount(({ actions, values }) => {
        const { jobRef } = values
        if (!jobRef) {
            return
        }
        // A stored job from another project cannot be read here.
        if (String(jobRef.teamId) !== String(values.currentTeamIdStrict)) {
            actions.setJobRef(null)
            return
        }
        // Polling, not a single read, so a failed first read is retried like any other poll.
        actions.loadJob()
        actions.resumeJob()
    }),
])
