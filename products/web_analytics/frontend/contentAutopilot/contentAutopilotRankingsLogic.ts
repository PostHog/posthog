export type contentAutopilotRankingsLogicType = MakeLogicType<
    contentAutopilotRankingsLogicValues,
    contentAutopilotRankingsLogicActions,
    Record<string, any>,
    contentAutopilotRankingsLogicMeta
>

export const contentAutopilotRankingsLogic = kea<contentAutopilotRankingsLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotRankingsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], contentAutopilotFiltersLogic, ['filters']],
        actions: [
            contentAutopilotFiltersLogic,
            ['setDays', 'setEngine', 'setTopic', 'setBrandedSegment', 'applyUrlFilters'],
        ],
    })),
    actions({
        loadRankings: true,
    }),
    loaders(({ values }) => ({
        rankings: [
            null as AEOPromptSetRankingsApi | null,
            {
                loadRankings: async (_, breakpoint) => {
                    try {
                        const rankings = await aeoPromptsRankings(
                            String(values.currentTeamIdStrict),
                            filtersToQueryParams(values.filters)
                        )
                        breakpoint()
                        return rankings
                    } catch (error) {
                        // A superseded request's failure must not replace newer rankings with an error
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        rankingsError: [
            null as ContentAutopilotPromptsError | null,
            {
                loadRankings: () => null,
                loadRankingsFailure: (_, { errorObject }) => promptsErrorFrom(errorObject),
            },
        ],
    }),
    selectors({
        chart: [
            (s) => [s.rankings],
            (rankings: AEOPromptSetRankingsApi | null): RankingsChart | null =>
                rankings ? rankingsChart(rankings) : null,
        ],
    }),
    listeners(({ actions }) => ({
        setDays: () => actions.loadRankings(),
        setEngine: () => actions.loadRankings(),
        setTopic: () => actions.loadRankings(),
        setBrandedSegment: () => actions.loadRankings(),
        applyUrlFilters: () => actions.loadRankings(),
    })),
    afterMount(({ actions }) => {
        actions.loadRankings()
    }),
])
