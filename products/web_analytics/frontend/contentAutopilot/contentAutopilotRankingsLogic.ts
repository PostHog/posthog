import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { aeoPromptsRankings } from 'products/web_analytics/frontend/generated/api'
import type {
    BrandedSegmentEnumApi,
    AEOPromptSetRankingsApi,
} from 'products/web_analytics/frontend/generated/api.schemas'

import { contentAutopilotBrandedLogic } from './contentAutopilotBrandedLogic'
import { ContentAutopilotPromptsError, promptsErrorFrom } from './contentAutopilotPromptsLogic'
import { RankingsChart, rankingsChart } from './rankingsReport'

export const RANKINGS_DAYS = 30

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotRankingsLogicValues {
    brandedSegment: BrandedSegmentEnumApi // contentAutopilotBrandedLogic
    currentTeamIdStrict: number | string // teamLogic
    chart: RankingsChart | null
    rankings: AEOPromptSetRankingsApi | null
    rankingsError: ContentAutopilotPromptsError | null
    rankingsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotRankingsLogicActions {
    setBrandedSegment: (
        brandedSegment: BrandedSegmentEnumApi,
        tab: import('./contentAutopilotBrandedLogic').BrandedSegmentTab
    ) => {
        brandedSegment: BrandedSegmentEnumApi
        tab: import('./contentAutopilotBrandedLogic').BrandedSegmentTab
    } // contentAutopilotBrandedLogic
    loadRankings: () => {
        value: true
    }
    loadRankingsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRankingsSuccess: (
        rankings: AEOPromptSetRankingsApi,
        payload?: {
            value: true
        }
    ) => {
        rankings: AEOPromptSetRankingsApi
        payload?: {
            value: true
        }
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotRankingsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        chart: (rankings: AEOPromptSetRankingsApi | null) => RankingsChart | null
    }
}

export type contentAutopilotRankingsLogicType = MakeLogicType<
    contentAutopilotRankingsLogicValues,
    contentAutopilotRankingsLogicActions,
    Record<string, any>,
    contentAutopilotRankingsLogicMeta
>

export const contentAutopilotRankingsLogic = kea<contentAutopilotRankingsLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotRankingsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], contentAutopilotBrandedLogic, ['brandedSegment']],
        actions: [contentAutopilotBrandedLogic, ['setBrandedSegment']],
    })),
    actions({
        loadRankings: true,
    }),
    loaders(({ values }) => ({
        rankings: [
            null as AEOPromptSetRankingsApi | null,
            {
                loadRankings: async (_, breakpoint) => {
                    try {
                        const rankings = await aeoPromptsRankings(String(values.currentTeamIdStrict), {
                            days: RANKINGS_DAYS,
                            branded: values.brandedSegment,
                        })
                        breakpoint()
                        return rankings
                    } catch (error) {
                        // A superseded request's failure must not replace newer rankings with an error
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        rankingsError: [
            null as ContentAutopilotPromptsError | null,
            {
                loadRankings: () => null,
                loadRankingsFailure: (_, { errorObject }) => promptsErrorFrom(errorObject),
            },
        ],
    }),
    selectors({
        chart: [
            (s) => [s.rankings],
            (rankings: AEOPromptSetRankingsApi | null): RankingsChart | null =>
                rankings ? rankingsChart(rankings) : null,
        ],
    }),
    listeners(({ actions }) => ({
        setBrandedSegment: () => actions.loadRankings(),
    })),
    afterMount(({ actions }) => {
        actions.loadRankings()
    }),
])
