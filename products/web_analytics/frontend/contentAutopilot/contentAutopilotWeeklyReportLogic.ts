import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { SubscriptionResourceTypes } from '~/types'

import { aeoPromptsWeeklyReport } from 'products/web_analytics/frontend/generated/api'
import type { AEOWeeklyReportApi } from 'products/web_analytics/frontend/generated/api.schemas'

import { ContentAutopilotPromptsError, promptsErrorFrom } from './contentAutopilotPromptsLogic'

export const WEEKLY_REPORT_SUBSCRIPTION_TITLE = 'Weekly AI visibility report'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotWeeklyReportLogicValues {
    currentTeamIdStrict: number | string // teamLogic
    weeklyReport: AEOWeeklyReportApi | null
    weeklyReportError: ContentAutopilotPromptsError | null
    weeklyReportLoading: boolean
    weeklyReportPreviewOpen: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface contentAutopilotWeeklyReportLogicActions {
    closeWeeklyReportPreview: () => {
        value: true
    }
    loadWeeklyReport: () => {
        value: true
    }
    loadWeeklyReportFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadWeeklyReportSuccess: (
        weeklyReport: AEOWeeklyReportApi,
        payload?: {
            value: true
        }
    ) => {
        weeklyReport: AEOWeeklyReportApi
        payload?: {
            value: true
        }
    }
    openWeeklyReportPreview: () => {
        value: true
    }
    sendWeeklyReport: (source: 'overview' | 'preview') => {
        source: 'overview' | 'preview'
    }
}

export type contentAutopilotWeeklyReportLogicType = MakeLogicType<
    contentAutopilotWeeklyReportLogicValues,
    contentAutopilotWeeklyReportLogicActions
>

export const contentAutopilotWeeklyReportLogic = kea<contentAutopilotWeeklyReportLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotWeeklyReportLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
    })),
    actions({
        loadWeeklyReport: true,
        openWeeklyReportPreview: true,
        closeWeeklyReportPreview: true,
        sendWeeklyReport: (source: 'overview' | 'preview') => ({ source }),
    }),
    loaders(({ values }) => ({
        weeklyReport: [
            null as AEOWeeklyReportApi | null,
            {
                loadWeeklyReport: async (_, breakpoint) => {
                    try {
                        const report = await aeoPromptsWeeklyReport(String(values.currentTeamIdStrict))
                        breakpoint()
                        return report
                    } catch (error) {
                        // A superseded request's failure must not replace the newer report with an error
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        weeklyReportPreviewOpen: [
            false,
            {
                openWeeklyReportPreview: () => true,
                closeWeeklyReportPreview: () => false,
            },
        ],
        weeklyReportError: [
            null as ContentAutopilotPromptsError | null,
            {
                loadWeeklyReport: () => null,
                loadWeeklyReportFailure: (_, { errorObject }) => promptsErrorFrom(errorObject),
            },
        ],
    }),
    listeners(({ actions }) => ({
        openWeeklyReportPreview: () => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot weekly report previewed')
            actions.loadWeeklyReport()
        },
        sendWeeklyReport: ({ source }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot weekly report send clicked', { source })
            actions.closeWeeklyReportPreview()
            router.actions.push(urls.subscriptionNew(), {
                resource_type: SubscriptionResourceTypes.AiVisibilityReport,
                frequency: 'weekly',
                title: WEEKLY_REPORT_SUBSCRIPTION_TITLE,
            })
        },
    })),
])
