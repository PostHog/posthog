export const contentAutopilotPromptsLogic = kea<contentAutopilotPromptsLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotPromptsLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamIdStrict']] })),
    actions({
        loadAeoPrompts: true,
        setPromptsPage: (page: number) => ({ page }),
        setPromptsTopic: (topic: string | null) => ({ topic }),
        setShowArchived: (showArchived: boolean) => ({ showArchived }),
        setPromptActive: (promptId: string, active: boolean) => ({ promptId, active }),
        setPromptActiveSuccess: (prompt: AEOPromptApi) => ({ prompt }),
        setPromptActiveFailure: (promptId: string, active: boolean) => ({ promptId, active }),
    }),
    loaders(({ values }) => ({
        prompts: [
            null as PaginatedAEOPromptListApi | null,
            {
                loadAeoPrompts: async (_, breakpoint) => {
                    const response = await aeoPromptsList(String(values.currentTeamIdStrict), {
                        limit: PROMPTS_PAGE_SIZE,
                        offset: (values.promptsPage - 1) * PROMPTS_PAGE_SIZE,
                        topic: values.promptsTopic ?? undefined,
                        include_archived: values.showArchived || undefined,
                    })
                    breakpoint()
                    return response
                },
            },
        ],
        promptTopics: [
            [] as AEOPromptTopicApi[],
            {
                loadAeoPromptTopics: async () => aeoPromptsTopics(String(values.currentTeamIdStrict)),
            },
        ],
    })),
    reducers({
        prompts: {
            setPromptActive: (state, { promptId, active }) => withPromptActive(state, promptId, active),
            setPromptActiveSuccess: (state, { prompt }) => withPromptActive(state, prompt.id, prompt.active),
            setPromptActiveFailure: (state, { promptId, active }) => withPromptActive(state, promptId, !active),
        },
        promptActiveUpdating: [
            {} as Record<string, boolean>,
            {
                setPromptActive: (state, { promptId }) => ({ ...state, [promptId]: true }),
                setPromptActiveSuccess: (state, { prompt }) => omitKey(state, prompt.id),
                setPromptActiveFailure: (state, { promptId }) => omitKey(state, promptId),
            },
        ],
        promptsPage: [
            1,
            {
                setPromptsPage: (_, { page }) => page,
                setPromptsTopic: () => 1,
                setShowArchived: () => 1,
            },
        ],
        showArchived: [
            false,
            {
                setShowArchived: (_, { showArchived }) => showArchived,
            },
        ],
        promptsTopic: [
            null as string | null,
            {
                setPromptsTopic: (_, { topic }) => topic,
            },
        ],
        promptsError: [
            null as ContentAutopilotPromptsError | null,
            {
                loadAeoPrompts: () => null,
                loadAeoPromptsFailure: (_, { errorObject }) => promptsErrorFrom(errorObject),
            },
        ],
    }),
    selectors({
        promptEngines: [
            (s) => [s.prompts],
            (prompts: PaginatedAEOPromptListApi | null): string[] =>
                sortEngines(
                    (prompts?.results ?? []).flatMap((prompt) => prompt.latest_checks.map((check) => check.engine))
                ),
        ],
    }),
    listeners(({ actions, values }) => ({
        setPromptActive: async ({ promptId, active }) => {
            try {
                const prompt = await aeoPromptsPartialUpdate(String(values.currentTeamIdStrict), promptId, { active })
                actions.setPromptActiveSuccess(prompt)
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics content autopilot prompt toggled', { active })
            } catch {
                actions.setPromptActiveFailure(promptId, active)
                lemonToast.error(
                    active ? "Couldn't turn the prompt on. Try again." : "Couldn't turn the prompt off. Try again."
                )
            }
        },
        setPromptsPage: () => actions.loadAeoPrompts(),
        setShowArchived: ({ showArchived }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot prompts archived shown', { show_archived: showArchived })
            actions.loadAeoPrompts()
        },
        setPromptsTopic: ({ topic }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot prompts topic changed', {
                filtered: topic !== null,
            })
            actions.loadAeoPrompts()
        },
    })),
    afterMount(({ actions }) => {
        // pinned: analytics event name, renaming it breaks dashboards
        posthog.capture('web analytics content autopilot prompts viewed')
        actions.loadAeoPrompts()
        actions.loadAeoPromptTopics()
    }),
])
