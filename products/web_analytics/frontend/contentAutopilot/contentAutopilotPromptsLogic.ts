import {
    aeoPromptsList,
    aeoPromptsPartialUpdate,
    aeoPromptsTopics,
} from 'products/web_analytics/frontend/generated/api'
import type {
    AEOPromptApi,
    AEOPromptTopicApi,
    PaginatedAEOPromptListApi,
} from 'products/web_analytics/frontend/generated/api.schemas'

import { sortEngines } from './utils'

export const PROMPTS_PAGE_SIZE = 50

export type ContentAutopilotPromptsError = 'forbidden' | 'failed'

const promptsErrorFrom = (error: unknown): ContentAutopilotPromptsError =>
    error instanceof ApiError && error.status === 403 ? 'forbidden' : 'failed'

const omitKey = (record: Record<string, boolean>, key: string): Record<string, boolean> => {
    const { [key]: _omitted, ...rest } = record
    return rest
}

const withPromptActive = (
    prompts: PaginatedAEOPromptListApi | null,
    promptId: string,
    active: boolean
): PaginatedAEOPromptListApi | null =>
    prompts && {
        ...prompts,
        results: prompts.results.map((prompt) => (prompt.id === promptId ? { ...prompt, active } : prompt)),
    }

