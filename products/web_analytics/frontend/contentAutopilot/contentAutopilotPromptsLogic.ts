export const contentAutopilotPromptsLogic = kea<contentAutopilotPromptsLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotPromptsLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamIdStrict'],
            aiVisibilityEnginesLogic,
            ['engines'],
            contentAutopilotFiltersLogic,
            ['filters'],
            contentAutopilotSetupLogic,
            ['setupContext'],
        ],
        actions: [
            contentAutopilotFiltersLogic,
            ['setDates', 'setEngine', 'setTopic', 'setBrandedSegment', 'applyUrlFilters'],
            contentAutopilotSetupLogic,
            ['loadSetupContext'],
            aiVisibilityTopicsLogic,
            ['loadPromptTopics', 'topicChangeSuccess'],
        ],
    })),
    actions({
        loadAeoPrompts: true,
        setPromptsPage: (page: number) => ({ page }),
        setShowArchived: (showArchived: boolean) => ({ showArchived }),
        setNeedsImprovement: (needsImprovement: boolean) => ({ needsImprovement }),
        setPromptActive: (promptId: string, active: boolean) => ({ promptId, active }),
        setPromptActiveSuccess: (prompt: AEOPromptApi) => ({ prompt }),
        setPromptActiveFailure: (promptId: string, active: boolean) => ({ promptId, active }),
        openAddPrompts: true,
        closeAddPrompts: true,
        addPrompts: (text: string, topic: string) => ({ text, topic }),
        addPromptsSuccess: (result: AEOPromptImportResultApi) => ({ result }),
        addPromptsFailure: true,
        togglePromptSelected: (promptId: string) => ({ promptId }),
        selectPrompts: (promptIds: string[]) => ({ promptIds }),
        clearPromptSelection: true,
        openSetTopic: true,
        closeSetTopic: true,
        setPromptsTopic: (topic: string) => ({ topic }),
        setPromptsTopicSuccess: (topic: string, change: AEOPromptTopicChangeApi) => ({ topic, change }),
        setPromptsTopicFailure: true,
    }),
    loaders(({ values }) => ({
        prompts: [
            null as PaginatedAEOPromptListApi | null,
            {
                loadAeoPrompts: async (_, breakpoint) => {
                    try {
                        const { dateFrom, dateTo, engine, topic, branded } = values.filters
                        const response = await aeoPromptsList(String(values.currentTeamIdStrict), {
                            limit: PROMPTS_PAGE_SIZE,
                            offset: (values.promptsPage - 1) * PROMPTS_PAGE_SIZE,
                            topic: topic ?? undefined,
                            include_archived: values.showArchived || undefined,
                            branded: branded === 'all' ? undefined : branded === 'branded',
                            // The window and the engine only narrow which answers count for needs improvement.
                            ...(values.needsImprovement
                                ? {
                                      needs_improvement: true,
                                      date_from: dateFrom,
                                      ...(dateTo !== null ? { date_to: dateTo } : {}),
                                      ...(engine !== null ? { engine } : {}),
                                  }
                                : {}),
                        })
                        breakpoint()
                        return response
                    } catch (error) {
                        // A superseded request's failure must not show an error over the newer results
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        prompts: {
            setPromptActive: (state, { promptId, active }) => withPromptActive(state, promptId, active),
            setPromptActiveSuccess: (state, { prompt }) => withPromptActive(state, prompt.id, prompt.active),
            setPromptActiveFailure: (state, { promptId, active }) => withPromptActive(state, promptId, !active),
        },
        promptActiveUpdating: [
            {} as Record<string, boolean>,
            {
                setPromptActive: (state, { promptId }) => ({ ...state, [promptId]: true }),
                setPromptActiveSuccess: (state, { prompt }) => omitKey(state, prompt.id),
                setPromptActiveFailure: (state, { promptId }) => omitKey(state, promptId),
            },
        ],
        addPromptsOpen: [
            false,
            {
                openAddPrompts: () => true,
                closeAddPrompts: () => false,
                addPromptsSuccess: () => false,
            },
        ],
        addPromptsSubmitting: [
            false,
            {
                addPrompts: () => true,
                addPromptsSuccess: () => false,
                addPromptsFailure: () => false,
            },
        ],
        promptsPage: [
            1,
            {
                setPromptsPage: (_, { page }) => page,
                setShowArchived: () => 1,
                setNeedsImprovement: () => 1,
                setDates: () => 1,
                setEngine: () => 1,
                setTopic: () => 1,
                setBrandedSegment: () => 1,
                applyUrlFilters: () => 1,
            },
        ],
        needsImprovement: [
            false,
            {
                setNeedsImprovement: (_, { needsImprovement }) => needsImprovement,
            },
        ],
        showArchived: [
            false,
            {
                setShowArchived: (_, { showArchived }) => showArchived,
            },
        ],
        // Every reload can bring other rows, so a selection only lasts while the same page shows. A row picked
        // while the reload ran is kept only if it is still on the page that arrives, so Set topic never changes
        // a prompt the table no longer shows.
        selectedPromptIds: [
            [] as string[],
            {
                togglePromptSelected: (state, { promptId }) =>
                    state.includes(promptId) ? state.filter((id) => id !== promptId) : [...state, promptId],
                selectPrompts: (_, { promptIds }) => promptIds,
                clearPromptSelection: () => [],
                loadAeoPrompts: () => [],
                loadAeoPromptsSuccess: (state, { prompts }) =>
                    state.filter((id) => prompts.results.some((prompt) => prompt.id === id && !prompt.archived_at)),
            },
        ],
        setTopicOpen: [
            false,
            {
                openSetTopic: () => true,
                closeSetTopic: () => false,
                setPromptsTopicSuccess: () => false,
            },
        ],
        setTopicSaving: [
            false,
            {
                setPromptsTopic: () => true,
                setPromptsTopicSuccess: () => false,
                setPromptsTopicFailure: () => false,
            },
        ],
        promptsError: [
            null as ContentAutopilotPromptsError | null,
            {
                loadAeoPrompts: () => null,
                loadAeoPromptsFailure: (_, { errorObject }) => promptsErrorFrom(errorObject),
            },
        ],
    }),
    selectors({
        // Archived prompts accept no edit until they are restored, so they can't be picked.
        selectablePromptIds: [
            (s) => [s.prompts],
            (prompts: PaginatedAEOPromptListApi | null): string[] =>
                (prompts?.results ?? []).filter((prompt) => !prompt.archived_at).map((prompt) => prompt.id),
        ],
        promptLimitReached: [
            (s) => [s.setupContext],
            (setupContext: AEOSetupContextApi | null): boolean =>
                !!setupContext && setupContext.active_prompts >= setupContext.max_active_prompts,
        ],
        promptEngines: [
            (s) => [s.prompts, s.engines, s.filters, s.needsImprovement],
            (
                prompts: PaginatedAEOPromptListApi | null,
                engines: AEOEngineSettingApi[] | null,
                filters: AiVisibilityFilters,
                needsImprovement: boolean
            ): string[] =>
                // Needs improvement narrowed to one engine shows that engine's column alone. Otherwise one column per
                // engine the project runs now, and until the settings load, the engines the prompts were checked on.
                needsImprovement && filters.engine !== null
                    ? [filters.engine]
                    : sortEngines(
                          engines
                              ? engines
                                    .filter((engine) => engine.enabled && engine.available)
                                    .map((engine) => engine.engine)
                              : (prompts?.results ?? []).flatMap((prompt) =>
                                    prompt.latest_checks.map((check) => check.engine)
                                )
                      ),
        ],
    }),
    listeners(({ actions, values }) => ({
        setPromptActive: async ({ promptId, active }) => {
            try {
                const prompt = await aeoPromptsPartialUpdate(String(values.currentTeamIdStrict), promptId, { active })
                actions.setPromptActiveSuccess(prompt)
                actions.loadSetupContext()
                // pinned: analytics event name, renaming it breaks dashboards
                posthog.capture('web analytics content autopilot prompt toggled', { active })
            } catch (error) {
                actions.setPromptActiveFailure(promptId, active)
                const detail = error instanceof ApiError && error.status === 400 ? error.detail : null
                lemonToast.error(
                    detail ||
                        (active
                            ? "Couldn't turn the prompt on. Try again."
                            : "Couldn't turn the prompt off. Try again.")
                )
            }
        },
        addPrompts: async ({ text, topic }) => {
            const prompts = promptLines(text).map((prompt) => ({ prompt, topic: topic.trim() || undefined }))
            try {
                const result = await aeoPromptsBulkImport(String(values.currentTeamIdStrict), { prompts })
                actions.addPromptsSuccess(result)
            } catch (error) {
                actions.addPromptsFailure()
                // A 400 explains why the prompts were refused, so show it rather than asking for a retry.
                const detail = error instanceof ApiError && error.status === 400 ? error.detail : null
                lemonToast.error(detail || "Couldn't add the prompts. Try again.")
            }
        },
        addPromptsSuccess: ({ result }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot prompts added', {
                created: result.created,
                updated: result.updated,
                skipped: result.skipped,
            })
            lemonToast.success(promptImportMessage(result))
            actions.loadAeoPrompts()
            actions.loadSetupContext()
            // New prompts can bring new topics to the filter bar.
            actions.loadPromptTopics()
        },
        setPromptsTopic: async ({ topic }) => {
            try {
                const change = await aeoPromptsBulkSetTopic(String(values.currentTeamIdStrict), {
                    prompt_ids: values.selectedPromptIds,
                    topic,
                })
                actions.setPromptsTopicSuccess(topic, change)
            } catch (error) {
                actions.setPromptsTopicFailure()
                const detail = error instanceof ApiError && [400, 404].includes(error.status ?? 0) ? error.detail : null
                lemonToast.error(detail || "Couldn't change the topic. Try again.")
            }
        },
        setPromptsTopicSuccess: ({ topic, change }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics ai visibility prompts topic set', {
                prompts: change.prompts,
                removed: topic === '',
            })
            lemonToast.success(setTopicMessage(topic, change))
            actions.loadAeoPrompts()
            actions.loadPromptTopics()
        },
        topicChangeSuccess: () => actions.loadAeoPrompts(),
        setPromptsPage: () => actions.loadAeoPrompts(),
        setShowArchived: ({ showArchived }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot prompts archived shown', { show_archived: showArchived })
            actions.loadAeoPrompts()
        },
        setNeedsImprovement: ({ needsImprovement }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot prompts needs improvement filtered', {
                needs_improvement: needsImprovement,
            })
            actions.loadAeoPrompts()
        },
        setDates: () => actions.loadAeoPrompts(),
        setEngine: () => actions.loadAeoPrompts(),
        setTopic: () => actions.loadAeoPrompts(),
        setBrandedSegment: () => actions.loadAeoPrompts(),
        applyUrlFilters: () => actions.loadAeoPrompts(),
    })),
    afterMount(({ actions }) => {
        // pinned: analytics event name, renaming it breaks dashboards
        posthog.capture('web analytics content autopilot prompts viewed')
        actions.loadAeoPrompts()
    }),
])
