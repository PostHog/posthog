const AI_VISIBILITY_PATH = '/web/content-autopilot'

/** The filters the Overview, Rankings, Prompts and Keywords tabs share, kept in the URL so a link keeps them. */
export const contentAutopilotFiltersLogic = kea<contentAutopilotFiltersLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotFiltersLogic']),
    actions({
        /** A range picked in the date filter. It becomes the filter only when the API can serve it. */
        pickDates: (dateFrom: string, dateTo: string | null, tab: AiVisibilityFilterTab) => ({ dateFrom, dateTo, tab }),
        setDates: (dateFrom: string, dateTo: string | null, tab: AiVisibilityFilterTab) => ({ dateFrom, dateTo, tab }),
        setEngine: (engine: string | null, tab: AiVisibilityFilterTab) => ({ engine, tab }),
        setTopic: (topic: string | null, tab: AiVisibilityFilterTab) => ({ topic, tab }),
        setBrandedSegment: (brandedSegment: BrandedSegmentEnumApi, tab: AiVisibilityFilterTab) => ({
            brandedSegment,
            tab,
        }),
        applyUrlFilters: (filters: Partial<AiVisibilityFilters>) => ({ filters }),
    }),
    reducers({
        dateFrom: [
            DEFAULT_AI_VISIBILITY_DATE_FROM as string,
            {
                setDates: (_, { dateFrom }) => dateFrom,
                applyUrlFilters: (state, { filters }) => filters.dateFrom ?? state,
            },
        ],
        dateTo: [
            null as string | null,
            {
                setDates: (_, { dateTo }) => dateTo,
                applyUrlFilters: (state, { filters }) => (filters.dateTo !== undefined ? filters.dateTo : state),
            },
        ],
        engine: [
            null as string | null,
            {
                setEngine: (_, { engine }) => engine,
                applyUrlFilters: (state, { filters }) => (filters.engine !== undefined ? filters.engine : state),
            },
        ],
        topic: [
            null as string | null,
            {
                setTopic: (_, { topic }) => topic,
                applyUrlFilters: (state, { filters }) => (filters.topic !== undefined ? filters.topic : state),
            },
        ],
        // Non-branded by default, because a prompt that names the brand almost always gets an answer that mentions it.
        // The last choice persists per browser, and a link that carries a segment overrides it.
        brandedSegment: [
            BrandedSegmentEnumApi.NonBranded as BrandedSegmentEnumApi,
            // pinned: local storage key, so the segment people chose before survives the logic's rename
            {
                persist: true,
                storageKey: 'products.webAnalytics.contentAutopilot.contentAutopilotBrandedLogic.brandedSegment',
            },
            {
                setBrandedSegment: (_, { brandedSegment }) => brandedSegment,
                applyUrlFilters: (state, { filters }) => filters.branded ?? state,
            },
        ],
    }),
    selectors({
        filters: [
            (s) => [s.dateFrom, s.dateTo, s.engine, s.topic, s.brandedSegment],
            (
                dateFrom: string,
                dateTo: string | null,
                engine: string | null,
                topic: string | null,
                brandedSegment: BrandedSegmentEnumApi
            ): AiVisibilityFilters => ({ dateFrom, dateTo, engine, topic, branded: brandedSegment }),
        ],
    }),
    listeners(({ actions }) => ({
        pickDates: ({ dateFrom, dateTo, tab }) => {
            const problem = dateRangeProblem(dateFrom, dateTo)
            if (problem) {
                lemonToast.error(problem)
                return
            }
            actions.setDates(dateFrom, dateTo, tab)
        },
        setBrandedSegment: ({ brandedSegment, tab }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot branded segment changed', {
                segment: brandedSegment,
                tab,
            })
        },
        setDates: ({ dateFrom, dateTo, tab }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot filter changed', {
                filter: 'date_range',
                date_from: dateFrom,
                date_to: dateTo,
                tab,
            })
        },
        setEngine: ({ engine, tab }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot filter changed', { filter: 'engine', engine, tab })
        },
        setTopic: ({ topic, tab }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot filter changed', {
                filter: 'topic',
                filtered: topic !== null,
                tab,
            })
        },
    })),
    actionToUrl(({ values }) => {
        const toUrl = ():
            | [string, Record<string, unknown>, Record<string, unknown>, { replace: boolean }]
            | undefined => {
            const { pathname } = router.values.location
            const { searchParams, hashParams } = router.values
            // The prompt detail page keeps the filters too, so closing a prompt returns to the same view.
            if (!pathname.includes(AI_VISIBILITY_PATH)) {
                return undefined
            }
            const nextSearchParams = withFilterSearchParams(searchParams, values.filters)
            return objectsEqual(nextSearchParams, searchParams)
                ? undefined
                : [pathname, nextSearchParams, hashParams, { replace: true }]
        }
        return {
            setDates: toUrl,
            setEngine: toUrl,
            setTopic: toUrl,
            setBrandedSegment: toUrl,
        }
    }),
    urlToAction(({ actions, values }) => {
        const fromUrl = (_: Record<string, string | undefined>, searchParams: Record<string, unknown>): void => {
            const filters = filtersFromSearchParams(searchParams)
            const changed = Object.entries(filters).some(
                ([key, value]) => values.filters[key as keyof AiVisibilityFilters] !== value
            )
            if (changed) {
                actions.applyUrlFilters(filters)
            }
        }
        return {
            [AI_VISIBILITY_PATH]: fromUrl,
            [`${AI_VISIBILITY_PATH}/prompts/:promptId`]: fromUrl,
        }
    }),
])
