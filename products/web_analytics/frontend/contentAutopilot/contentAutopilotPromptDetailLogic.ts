export const contentAutopilotPromptDetailLogic = kea<contentAutopilotPromptDetailLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'contentAutopilotPromptDetailLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
        actions: [
            contentAutopilotPromptsLogic,
            ['setPromptActive', 'setPromptActiveSuccess', 'setPromptActiveFailure'],
        ],
    })),
    actions({
        openPromptDetail: (promptId: string) => ({ promptId }),
        closePromptDetail: true,
        selectEngine: (engine: string) => ({ engine }),
        selectCheck: (check: AEOPromptCheckApi) => ({ check }),
        setChecksPage: (page: number) => ({ page }),
    }),
    loaders(({ values }) => ({
        prompt: [
            null as AEOPromptApi | null,
            {
                loadAeoPrompt: async (promptId: string, breakpoint) => {
                    const prompt = await aeoPromptsRetrieve(String(values.currentTeamIdStrict), promptId)
                    breakpoint()
                    return prompt
                },
            },
        ],
        stats: [
            null as AEOPromptStatsApi | null,
            {
                loadAeoPromptStats: async (promptId: string, breakpoint) => {
                    const stats = await aeoPromptsStats(String(values.currentTeamIdStrict), promptId)
                    breakpoint()
                    return stats
                },
            },
        ],
        latestChecks: [
            {} as Record<string, AEOPromptCheckApi>,
            {
                loadAeoPromptLatestChecks: async (
                    { promptId, engines }: { promptId: string; engines: string[] },
                    breakpoint
                ) => {
                    const pages = await Promise.all(
                        engines.map((engine) =>
                            aeoPromptsChecks(String(values.currentTeamIdStrict), promptId, { engine, limit: 1 })
                        )
                    )
                    breakpoint()
                    return Object.fromEntries(
                        pages.flatMap((page) => page.results.slice(0, 1)).map((check) => [check.engine, check])
                    )
                },
            },
        ],
        checks: [
            null as PaginatedAEOPromptCheckListApi | null,
            {
                loadAeoPromptChecks: async (_: void, breakpoint) => {
                    if (!values.promptId) {
                        return null
                    }
                    const page = await aeoPromptsChecks(String(values.currentTeamIdStrict), values.promptId, {
                        limit: PROMPT_CHECKS_PAGE_SIZE,
                        offset: (values.checksPage - 1) * PROMPT_CHECKS_PAGE_SIZE,
                    })
                    breakpoint()
                    return page
                },
            },
        ],
    })),
    reducers({
        promptId: [
            null as string | null,
            {
                openPromptDetail: (_, { promptId }) => promptId,
                closePromptDetail: () => null,
            },
        ],
        prompt: {
            openPromptDetail: () => null,
            setPromptActive: (state, { promptId, active }) => (state?.id === promptId ? { ...state, active } : state),
            setPromptActiveSuccess: (state, { prompt }) => (state?.id === prompt.id ? prompt : state),
            setPromptActiveFailure: (state, { promptId, active }) =>
                state?.id === promptId ? { ...state, active: !active } : state,
        },
        stats: { openPromptDetail: () => null },
        latestChecks: { openPromptDetail: () => ({}) },
        checks: { openPromptDetail: () => null },
        checksPage: [
            1,
            {
                openPromptDetail: () => 1,
                setChecksPage: (_, { page }) => page,
            },
        ],
        selectedEngine: [
            null as string | null,
            {
                openPromptDetail: () => null,
                selectEngine: (_, { engine }) => engine,
                selectCheck: (_, { check }) => check.engine,
            },
        ],
        selectedCheck: [
            null as AEOPromptCheckApi | null,
            {
                openPromptDetail: () => null,
                selectEngine: () => null,
                selectCheck: (_, { check }) => check,
            },
        ],
        detailError: [
            null as ContentAutopilotPromptDetailError | null,
            {
                openPromptDetail: () => null,
                loadAeoPromptFailure: (_, { errorObject }) =>
                    errorObject instanceof ApiError && errorObject.status === 404 ? 'not_found' : 'failed',
                loadAeoPromptStatsFailure: (state) => state ?? 'failed',
            },
        ],
        latestChecksFailed: [
            false,
            {
                loadAeoPromptLatestChecks: () => false,
                loadAeoPromptLatestChecksFailure: () => true,
            },
        ],
        checksFailed: [
            false,
            {
                loadAeoPromptChecks: () => false,
                loadAeoPromptChecksFailure: () => true,
            },
        ],
    }),
    selectors({
        engines: [
            (s) => [s.stats],
            (stats: AEOPromptStatsApi | null): string[] => sortEngines((stats?.engines ?? []).map((e) => e.engine)),
        ],
        activeEngine: [
            (s) => [s.selectedEngine, s.engines],
            (selectedEngine: string | null, engines: string[]): string | null => selectedEngine ?? engines[0] ?? null,
        ],
        shownCheck: [
            (s) => [s.selectedCheck, s.activeEngine, s.latestChecks],
            (
                selectedCheck: AEOPromptCheckApi | null,
                activeEngine: string | null,
                latestChecks: Record<string, AEOPromptCheckApi>
            ): AEOPromptCheckApi | null =>
                selectedCheck ?? (activeEngine ? (latestChecks[activeEngine] ?? null) : null),
        ],
        historyGrid: [
            (s) => [s.stats, s.engines],
            (stats: AEOPromptStatsApi | null, engines: string[]): PromptHistoryGrid | null =>
                stats ? promptHistoryGrid(stats, engines) : null,
        ],
        lastCheckedAt: [
            (s) => [s.stats],
            (stats: AEOPromptStatsApi | null): string | null =>
                (stats?.engines ?? []).reduce<string | null>(
                    (latest, engine) =>
                        latest === null || engine.last_checked_at > latest ? engine.last_checked_at : latest,
                    null
                ),
        ],
    }),
    listeners(({ actions, values }) => ({
        openPromptDetail: ({ promptId }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics content autopilot prompt detail viewed')
            actions.loadAeoPrompt(promptId)
            actions.loadAeoPromptStats(promptId)
            actions.loadAeoPromptChecks()
        },
        loadAeoPromptStatsSuccess: ({ stats, payload: promptId }) => {
            // Stats from a prompt the user already left must not drive the next prompt's answers.
            if (promptId && promptId === values.promptId) {
                actions.loadAeoPromptLatestChecks({
                    promptId,
                    engines: stats.engines.map((engine) => engine.engine),
                })
            }
        },
        setChecksPage: () => actions.loadAeoPromptChecks(),
    })),
])
