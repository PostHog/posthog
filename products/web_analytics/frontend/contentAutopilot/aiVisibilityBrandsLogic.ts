import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import { aeoBrandsList, aeoBrandsPartialUpdate } from 'products/web_analytics/frontend/generated/api'
import type {
    AEOBrandApi,
    BrandKindEnumApi,
    BrandStatusEnumApi,
    PatchedAEOBrandUpdateRequestApi,
} from 'products/web_analytics/frontend/generated/api.schemas'

export const BRANDS_PAGE_SIZE = 25

export interface BrandsPage {
    results: AEOBrandApi[]
    count: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiVisibilityBrandsLogicValues {
    currentTeamIdStrict: number | string // teamLogic
    brands: BrandsPage | null
    brandsError: boolean
    brandsLoading: boolean
    page: number
    search: string
    status: BrandStatusEnumApi
    updatingIds: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiVisibilityBrandsLogicActions {
    labelBrand: (
        id: string,
        kind: BrandKindEnumApi
    ) => {
        id: string
        kind: BrandKindEnumApi
    }
    loadBrands: () => {
        value: true
    }
    loadBrandsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadBrandsSuccess: (
        brands: {
            count: number
            results: AEOBrandApi[]
        },
        payload?: {
            value: true
        }
    ) => {
        brands: {
            count: number
            results: AEOBrandApi[]
        }
        payload?: {
            value: true
        }
    }
    setPage: (page: number) => {
        page: number
    }
    setSearch: (search: string) => {
        search: string
    }
    setStatus: (status: BrandStatusEnumApi) => {
        status: BrandStatusEnumApi
    }
    updateBrand: (
        id: string,
        change: PatchedAEOBrandUpdateRequestApi
    ) => {
        change: PatchedAEOBrandUpdateRequestApi
        id: string
    }
    updateBrandFailure: (id: string) => {
        id: string
    }
    updateBrandSuccess: (brand: AEOBrandApi) => {
        brand: AEOBrandApi
    }
}

export type aiVisibilityBrandsLogicType = MakeLogicType<aiVisibilityBrandsLogicValues, aiVisibilityBrandsLogicActions>

export const aiVisibilityBrandsLogic = kea<aiVisibilityBrandsLogicType>([
    path(['products', 'webAnalytics', 'contentAutopilot', 'aiVisibilityBrandsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
    })),
    actions({
        loadBrands: true,
        setStatus: (status: BrandStatusEnumApi) => ({ status }),
        setSearch: (search: string) => ({ search }),
        setPage: (page: number) => ({ page }),
        updateBrand: (id: string, change: PatchedAEOBrandUpdateRequestApi) => ({ id, change }),
        updateBrandSuccess: (brand: AEOBrandApi) => ({ brand }),
        updateBrandFailure: (id: string) => ({ id }),
        labelBrand: (id: string, kind: BrandKindEnumApi) => ({ id, kind }),
    }),
    reducers({
        status: ['suggested' as BrandStatusEnumApi, { setStatus: (_, { status }) => status }],
        search: ['', { setSearch: (_, { search }) => search }],
        page: [1, { setPage: (_, { page }) => page, setStatus: () => 1, setSearch: () => 1 }],
        brandsError: [
            false,
            {
                loadBrands: () => false,
                loadBrandsSuccess: () => false,
                loadBrandsFailure: () => true,
            },
        ],
        updatingIds: [
            [] as string[],
            {
                updateBrand: (state, { id }) => [...state, id],
                updateBrandSuccess: (state, { brand }) => state.filter((id) => id !== brand.id),
                updateBrandFailure: (state, { id }) => state.filter((updatingId) => updatingId !== id),
            },
        ],
    }),
    loaders(({ values }) => ({
        brands: [
            null as BrandsPage | null,
            {
                loadBrands: async (_, breakpoint) => {
                    await breakpoint(300)
                    const page = await aeoBrandsList(String(values.currentTeamIdStrict), {
                        status: values.status,
                        search: values.search || undefined,
                        limit: BRANDS_PAGE_SIZE,
                        offset: (values.page - 1) * BRANDS_PAGE_SIZE,
                    })
                    breakpoint()
                    return { results: page.results, count: page.count }
                },
            },
        ],
    })),
    reducers({
        // The saved brand replaces the row before the row unlocks, so a quick second edit starts from it.
        brands: {
            updateBrandSuccess: (state, { brand }) =>
                state ? { ...state, results: state.results.map((row) => (row.id === brand.id ? brand : row)) } : state,
        },
    }),
    listeners(({ actions, values }) => ({
        setStatus: () => actions.loadBrands(),
        setSearch: () => actions.loadBrands(),
        setPage: () => actions.loadBrands(),
        labelBrand: ({ id, kind }) => {
            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('web analytics ai visibility brand labeled', { kind })
            // Labeling a brand is the review, so it confirms it in the same call.
            actions.updateBrand(id, { kind, status: 'confirmed' })
        },
        updateBrand: async ({ id, change }) => {
            try {
                const brand = await aeoBrandsPartialUpdate(String(values.currentTeamIdStrict), id, change)
                actions.updateBrandSuccess(brand)
            } catch {
                lemonToast.error("Couldn't update the brand. Try again.")
                actions.updateBrandFailure(id)
                return
            }
            // A changed status moves the brand to another tab, so the page reloads.
            actions.loadBrands()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadBrands()
    }),
])
