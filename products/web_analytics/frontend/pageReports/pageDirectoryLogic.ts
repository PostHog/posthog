export const pageDirectoryLogic: LogicWrapper<pageDirectoryLogicType> = kea<pageDirectoryLogicType>([
    props({} as WebAnalyticsLogicProps),
    key((props) => props.context ?? 'web-analytics'),
    path((key) => ['products', 'webAnalytics', 'pageReports', 'pageDirectoryLogic', key]),
    connect((props: WebAnalyticsLogicProps) => ({
        actions: [dataNodeCollectionLogic({ key: WEB_ANALYTICS_DATA_COLLECTION_NODE_ID }), ['reloadAll']],
        values: [
            webAnalyticsLogic(props),
            [
                'dateFilter',
                'shouldFilterTestAccounts as filterTestAccounts',
                'compareFilter',
                'conversionGoal',
                'isPathCleaningEnabled',
                'webAnalyticsFilters',
            ],
            teamLogic,
            ['currentTeam'],
        ],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setSort: (sortBy: WebPageDirectorySortBy, sortDirection: PageDirectorySortDirection) => ({
            sortBy,
            sortDirection,
        }),
        nextPage: true,
        previousPage: true,
        resetPage: true,
        loadDriver: (refresh: boolean = false) => ({ refresh }),
        loadDriverSuccess: (rows: WebPageDirectoryRow[], hasMore: boolean, refresh: boolean = false) => ({
            rows,
            hasMore,
            refresh,
        }),
        loadDriverFailure: (error: string) => ({ error }),
        loadMetric: (metric: WebPageDirectoryMetric, pageKeys: string[], refresh: boolean = false) => ({
            metric,
            pageKeys,
            refresh,
        }),
        loadMetricSuccess: (metric: WebPageDirectoryMetric, rows: WebPageDirectoryRow[]) => ({ metric, rows }),
        loadMetricFailure: (metric: WebPageDirectoryMetric) => ({ metric }),
        loadSiteTotals: (refresh: boolean = false) => ({ refresh }),
        loadSiteTotalsSuccess: (siteTotals: WebPageDirectorySiteTotals | null) => ({ siteTotals }),
        loadSiteTotalsFailure: true,
        retryFailedMetrics: true,
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        sortBy: [WebPageDirectorySortBy.Visitors as WebPageDirectorySortBy, { setSort: (_, { sortBy }) => sortBy }],
        sortDirection: ['DESC' as PageDirectorySortDirection, { setSort: (_, { sortDirection }) => sortDirection }],
        pageIndex: [
            0,
            {
                nextPage: (state) => state + 1,
                previousPage: (state) => Math.max(0, state - 1),
                setSearch: () => 0,
                setSort: () => 0,
                resetPage: () => 0,
            },
        ],
        driverRows: [
            null as WebPageDirectoryRow[] | null,
            {
                loadDriverSuccess: (_, { rows }) => rows,
            },
        ],
        hasMore: [false, { loadDriverSuccess: (_, { hasMore }) => hasMore }],
        driverLoading: [
            false,
            {
                loadDriver: () => true,
                loadDriverSuccess: () => false,
                loadDriverFailure: () => false,
            },
        ],
        driverError: [
            null as string | null,
            {
                loadDriver: () => null,
                loadDriverFailure: (_, { error }) => error,
            },
        ],
        metricRows: [
            {} as Partial<Record<WebPageDirectoryMetric, Record<string, WebPageDirectoryRow>>>,
            {
                loadDriverSuccess: () => ({}),
                loadMetricSuccess: (state, { metric, rows }) => ({
                    ...state,
                    [metric]: Object.fromEntries(rows.map((row) => [row.page, row])),
                }),
            },
        ],
        metricLoading: [
            {} as Partial<Record<WebPageDirectoryMetric, boolean>>,
            {
                loadDriverSuccess: () => ({}),
                loadMetric: (state, { metric }) => ({ ...state, [metric]: true }),
                loadMetricSuccess: (state, { metric }) => ({ ...state, [metric]: false }),
                loadMetricFailure: (state, { metric }) => ({ ...state, [metric]: false }),
            },
        ],
        siteTotals: [
            null as WebPageDirectorySiteTotals | null,
            {
                loadSiteTotalsSuccess: (_, { siteTotals }) => siteTotals,
            },
        ],
        metricErrors: [
            {} as Partial<Record<WebPageDirectoryMetric, boolean>>,
            {
                loadDriverSuccess: () => ({}),
                loadMetric: (state, { metric }) => ({ ...state, [metric]: false }),
                loadMetricFailure: (state, { metric }) => ({ ...state, [metric]: true }),
            },
        ],
        siteTotalsError: [
            false,
            {
                loadSiteTotals: () => false,
                loadSiteTotalsSuccess: () => false,
                loadSiteTotalsFailure: () => true,
            },
        ],
    }),
    selectors({
        visibleMetrics: [
            (s) => [s.conversionGoal],
            (conversionGoal: WebAnalyticsConversionGoal | null): WebPageDirectoryMetric[] =>
                PAGE_DIRECTORY_METRICS.filter(
                    (metric) => metric !== WebPageDirectoryMetric.Conversions || !!conversionGoal
                ),
        ],
        baseQuery: [
            (s) => [
                s.dateFilter,
                s.compareFilter,
                s.conversionGoal,
                s.filterTestAccounts,
                s.isPathCleaningEnabled,
                s.webAnalyticsFilters,
            ],
            (
                dateFilter: DateFilterState,
                compareFilter: CompareFilter,
                conversionGoal: WebAnalyticsConversionGoal | null,
                filterTestAccounts: boolean,
                isPathCleaningEnabled: boolean,
                webAnalyticsFilters: WebAnalyticsPropertyFilters
            ): WebPageDirectoryQuery =>
                buildPageDirectoryBaseQuery({
                    dateFilter,
                    compareFilter,
                    conversionGoal,
                    filterTestAccounts,
                    isPathCleaningEnabled,
                    webAnalyticsFilters,
                }),
        ],
        driverQuery: [
            (s) => [s.baseQuery, s.search, s.sortBy, s.sortDirection, s.pageIndex],
            (
                baseQuery: WebPageDirectoryQuery,
                search: string,
                sortBy: WebPageDirectorySortBy,
                sortDirection: PageDirectorySortDirection,
                pageIndex: number
            ): WebPageDirectoryQuery => ({
                ...baseQuery,
                search: search.trim() || undefined,
                sortBy,
                sortDirection,
                metrics: [],
                limit: PAGE_DIRECTORY_PAGE_SIZE,
                offset: pageIndex * PAGE_DIRECTORY_PAGE_SIZE,
            }),
        ],
        directoryInput: [
            (s) => [s.driverQuery],
            (driverQuery: WebPageDirectoryQuery): string => JSON.stringify(driverQuery),
        ],
        siteTotalsQuery: [
            (s) => [s.baseQuery],
            (baseQuery: WebPageDirectoryQuery): WebPageDirectoryQuery => buildSiteTotalsQuery(baseQuery),
        ],
        siteTotalsInput: [
            (s) => [s.siteTotalsQuery],
            (siteTotalsQuery: WebPageDirectoryQuery): string => JSON.stringify(siteTotalsQuery),
        ],
        failedMetrics: [
            (s) => [s.metricErrors],
            (metricErrors: Partial<Record<WebPageDirectoryMetric, boolean>>): WebPageDirectoryMetric[] =>
                PAGE_DIRECTORY_METRICS.filter((metric) => metricErrors[metric]),
        ],
        hasServerLogs: [
            (s) => [s.siteTotals],
            (siteTotals: WebPageDirectorySiteTotals | null): boolean | null =>
                siteTotals ? siteTotals.serverLogs > 0 : null,
        ],
        rows: [
            (s) => [s.driverRows, s.metricRows],
            (
                driverRows: WebPageDirectoryRow[] | null,
                metricRows: Partial<Record<WebPageDirectoryMetric, Record<string, WebPageDirectoryRow>>>
            ): WebPageDirectoryRow[] => mergePageDirectoryRows(driverRows ?? [], metricRows),
        ],
        singleHost: [
            (s) => [s.driverRows],
            (driverRows: WebPageDirectoryRow[] | null): string | null => {
                const hosts = new Set((driverRows ?? []).map((row) => splitPageKey(row.page).host))
                const [host] = [...hosts]
                return hosts.size === 1 && host ? host : null
            },
        ],
        pastedUrl: [
            (s) => [s.search],
            (search: string): string | null => (looksLikePageUrl(search) ? search.trim() : null),
        ],
        directoryState: [
            (s) => [s.driverRows, s.driverError, s.search, s.pageIndex, s.sortBy, s.currentTeam],
            (
                driverRows: WebPageDirectoryRow[] | null,
                driverError: string | null,
                search: string,
                pageIndex: number,
                sortBy: WebPageDirectorySortBy,
                currentTeam: TeamPublicType | TeamType | null
            ): PageDirectoryState => {
                if (driverError) {
                    return 'error'
                }
                if (driverRows === null) {
                    return 'loading'
                }
                if (driverRows.length > 0 || pageIndex > 0) {
                    return 'ready'
                }
                if (search.trim()) {
                    return 'no-matches'
                }
                if (sortBy !== WebPageDirectorySortBy.Page && sortBy !== WebPageDirectorySortBy.Visitors) {
                    return 'no-metric-rows'
                }
                return currentTeam?.ingested_event ? 'no-traffic' : 'no-events'
            },
        ],
    }),
    listeners(({ values, actions, cache }) => {
        const startRequest = (key: string): CancellableRequest =>
            startCancellableRequest(cache.disposables, key, () => values.currentTeam?.id ?? null)
        const failureMessage = (error: unknown): string =>
            error instanceof Error ? error.message : 'Could not load pages'

        return {
            loadDriver: async ({ refresh }, breakpoint) => {
                for (const metric of PAGE_DIRECTORY_METRICS) {
                    cache.disposables.dispose(`metricRequest-${metric}`)
                }
                await breakpoint(300)
                const { signal, queryId, track } = startRequest('driverRequest')
                const query = values.driverQuery
                try {
                    const response = (await track(
                        performQuery(query, { signal }, refresh ? 'force_blocking' : 'blocking', queryId)
                    )) as WebPageDirectoryQueryResponse
                    breakpoint()
                    actions.loadDriverSuccess(response.results ?? [], !!response.hasMore, refresh)
                    if (query.search) {
                        posthog.capture('web analytics page reports searched', {
                            query_length: query.search.length,
                            result_count: response.results?.length ?? 0,
                            is_url: looksLikePageUrl(query.search),
                        })
                    }
                } catch (error) {
                    if (isCancelledRequest(error) || cache.disposables.isDisposed) {
                        return
                    }
                    breakpoint()
                    actions.loadDriverFailure(failureMessage(error))
                }
            },
            loadDriverSuccess: ({ rows, refresh }) => {
                const pageKeys = rows.map((row) => row.page)
                if (pageKeys.length === 0) {
                    return
                }
                const sortMetric = SORT_METRIC[values.sortBy]
                for (const metric of values.visibleMetrics) {
                    const notMeasured = metric === WebPageDirectoryMetric.AiCrawls && values.hasServerLogs === false
                    if (metric !== sortMetric && !notMeasured) {
                        actions.loadMetric(metric, pageKeys, refresh)
                    }
                }
            },
            loadMetric: async ({ metric, pageKeys, refresh }) => {
                const { signal, queryId, track } = startRequest(`metricRequest-${metric}`)
                const isStale = (): boolean =>
                    cache.disposables.isDisposed ||
                    (values.driverRows ?? []).map((row) => row.page).join('\n') !== pageKeys.join('\n')
                try {
                    const response = (await track(
                        performQuery(
                            { ...values.baseQuery, pageKeys, metrics: [metric] },
                            { signal },
                            refresh ? 'force_blocking' : 'blocking',
                            queryId
                        )
                    )) as WebPageDirectoryQueryResponse
                    if (!isStale()) {
                        actions.loadMetricSuccess(metric, response.results ?? [])
                    }
                } catch (error) {
                    if (isCancelledRequest(error) || isStale()) {
                        return
                    }
                    actions.loadMetricFailure(metric)
                }
            },
            loadSiteTotals: async ({ refresh }, breakpoint) => {
                await breakpoint(300)
                const { signal, queryId, track } = startRequest('siteTotalsRequest')
                try {
                    const response = (await track(
                        performQuery(
                            values.siteTotalsQuery,
                            { signal },
                            refresh ? 'force_blocking' : 'blocking',
                            queryId
                        )
                    )) as WebPageDirectoryQueryResponse
                    breakpoint()
                    actions.loadSiteTotalsSuccess(response.siteTotals ?? null)
                } catch (error) {
                    if (isCancelledRequest(error) || cache.disposables.isDisposed) {
                        return
                    }
                    actions.loadSiteTotalsFailure()
                }
            },
            retryFailedMetrics: () => {
                const pageKeys = (values.driverRows ?? []).map((row) => row.page)
                for (const metric of values.failedMetrics) {
                    actions.loadMetric(metric, pageKeys, true)
                }
            },
            loadSiteTotalsSuccess: ({ siteTotals }) => {
                const pageKeys = (values.driverRows ?? []).map((row) => row.page)
                const crawls = WebPageDirectoryMetric.AiCrawls
                if (
                    siteTotals &&
                    siteTotals.serverLogs > 0 &&
                    pageKeys.length > 0 &&
                    values.visibleMetrics.includes(crawls) &&
                    SORT_METRIC[values.sortBy] !== crawls &&
                    !values.metricRows[crawls] &&
                    !values.metricLoading[crawls]
                ) {
                    actions.loadMetric(crawls, pageKeys)
                }
            },
            setSort: ({ sortBy, sortDirection }) => {
                posthog.capture('web analytics page reports sorted', { column: sortBy, direction: sortDirection })
            },
            nextPage: () => {
                posthog.capture('web analytics page reports page changed', { page_index: values.pageIndex })
            },
            previousPage: () => {
                posthog.capture('web analytics page reports page changed', { page_index: values.pageIndex })
            },
            reloadAll: () => {
                actions.loadDriver(true)
                actions.loadSiteTotals(true)
            },
        }
    }),
    subscriptions(({ actions }) => ({
        baseQuery: (_, oldBaseQuery) => {
            if (oldBaseQuery) {
                actions.resetPage()
            }
        },
        directoryInput: () => {
            actions.loadDriver()
        },
        siteTotalsInput: () => {
            actions.loadSiteTotals()
        },
    })),
    afterMount(({ values }) => {
        posthog.capture('web analytics page reports directory viewed', {
            sort: values.sortBy,
            compare: !!values.compareFilter?.compare,
            has_conversion_goal: !!values.conversionGoal,
            path_cleaning: values.isPathCleaningEnabled,
        })
    }),
])
