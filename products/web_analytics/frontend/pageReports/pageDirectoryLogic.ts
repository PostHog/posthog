export const PAGE_DIRECTORY_PAGE_SIZE = 25

export type PageDirectorySortDirection = 'ASC' | 'DESC'

export type PageDirectoryState =
    | 'loading'
    | 'error'
    | 'no-events'
    | 'no-traffic'
    | 'no-matches'
    | 'no-metric-rows'
    | 'ready'

const PAGE_DIRECTORY_METRICS: WebPageDirectoryMetric[] = [
    WebPageDirectoryMetric.Visitors,
    WebPageDirectoryMetric.GoogleSearch,
    WebPageDirectoryMetric.AiReferrals,
    WebPageDirectoryMetric.AiCrawls,
    WebPageDirectoryMetric.Conversions,
    WebPageDirectoryMetric.TimeOnPage,
]

const SORT_METRIC: Record<WebPageDirectorySortBy, WebPageDirectoryMetric> = {
    [WebPageDirectorySortBy.Page]: WebPageDirectoryMetric.Visitors,
    [WebPageDirectorySortBy.Visitors]: WebPageDirectoryMetric.Visitors,
    [WebPageDirectorySortBy.GoogleSearch]: WebPageDirectoryMetric.GoogleSearch,
    [WebPageDirectorySortBy.AiReferrals]: WebPageDirectoryMetric.AiReferrals,
    [WebPageDirectorySortBy.AiCrawls]: WebPageDirectoryMetric.AiCrawls,
    [WebPageDirectorySortBy.Conversions]: WebPageDirectoryMetric.Conversions,
    [WebPageDirectorySortBy.TimeOnPage]: WebPageDirectoryMetric.TimeOnPage,
    [WebPageDirectorySortBy.BounceRate]: WebPageDirectoryMetric.BounceRate,
}

const mergePageDirectoryRows = (
    driverRows: WebPageDirectoryRow[],
    metricRows: Partial<Record<WebPageDirectoryMetric, Record<string, WebPageDirectoryRow>>>
): WebPageDirectoryRow[] =>
    driverRows.map((row) => {
        const merged: Record<string, unknown> = { ...row }
        for (const byPage of Object.values(metricRows)) {
            for (const [field, value] of Object.entries(byPage?.[row.page] ?? {})) {
                if (value != null && merged[field] == null) {
                    merged[field] = value
                }
            }
        }
        return merged as unknown as WebPageDirectoryRow
    })

