export const pageReportDetailLogic: LogicWrapper<pageReportDetailLogicType> = kea<pageReportDetailLogicType>([
    props({} as PageReportDetailLogicProps),
    key((props) => props.pageKey),
    path((key) => ['products', 'webAnalytics', 'pageReports', 'pageReportDetailLogic', key]),
    connect(() => ({
        values: [
            webAnalyticsLogic,
            [
                'dateFilter',
                'shouldFilterTestAccounts as filterTestAccounts',
                'compareFilter',
                'conversionGoal',
                'isPathCleaningEnabled',
                'webAnalyticsFilters',
                'selectedHost',
            ],
            teamLogic,
            ['currentTeam'],
            databaseTableListLogic,
            ['dataWarehouseTables', 'database', 'databaseLoadError'],
            pageReportsLogic,
            ['pageReportTab'],
        ],
        actions: [databaseTableListLogic, ['loadDatabase'], pageReportsLogic, ['setPageReportTab']],
    })),
    actions({
        hoverHealthCard: (card: PageHealthCard) => ({ card }),
        clickHealthCard: (card: PageHealthCard) => ({ card }),
        clickSearchConsoleConnect: true,
        clickOpenPage: true,
        clickHeaderMenuItem: (item: 'copy_link' | 'heatmap') => ({ item }),
        reloadHealth: true,
    }),
    reducers({
        failedLoads: [
            {} as Partial<Record<DetailLoad, boolean>>,
            {
                loadPageMetrics: (state) => ({ ...state, pageMetrics: false }),
                loadPageMetricsFailure: (state) => ({ ...state, pageMetrics: true }),
                loadSiteTotals: (state) => ({ ...state, siteTotals: false }),
                loadSiteTotalsFailure: (state) => ({ ...state, siteTotals: true }),
                loadAiAssistants: (state) => ({ ...state, aiAssistants: false }),
                loadAiAssistantsFailure: (state) => ({ ...state, aiAssistants: true }),
                loadGscSummary: (state) => ({ ...state, gscSummary: false }),
                loadGscSummaryFailure: (state) => ({ ...state, gscSummary: true }),
            },
        ],
    }),
    loaders(({ values, props, cache }) => {
        const run = <T>(
            key: DetailLoad | 'siteRates',
            breakpoint: BreakPointFunction,
            load: (request: CancellableRequest) => Promise<T>
        ): Promise<T> =>
            runCancellableRequest(cache.disposables, key, () => values.currentTeam?.id ?? null, breakpoint, load)
        const runQuery = <N extends DataNode>(
            key: DetailLoad | 'siteRates',
            query: N,
            breakpoint: BreakPointFunction
        ): Promise<NonNullable<N['response']>> =>
            run(key, breakpoint, ({ signal, queryId }) => performQuery(query, { signal }, 'blocking', queryId))

        return {
            pageMetrics: [
                null as WebPageDirectoryRow | null,
                {
                    loadPageMetrics: async (_, breakpoint) => {
                        await breakpoint(100)
                        const response = (await runQuery(
                            'pageMetrics',
                            { ...values.baseQuery, pageKeys: [props.pageKey], metrics: HEALTH_METRICS },
                            breakpoint
                        )) as WebPageDirectoryQueryResponse
                        return response.results?.[0] ?? null
                    },
                },
            ],
            siteTotals: [
                null as WebPageDirectorySiteTotals | null,
                {
                    loadSiteTotals: async (_, breakpoint) => {
                        await breakpoint(100)
                        const filters = {
                            dateFilter: values.dateFilter,
                            compareFilter: values.compareFilter,
                            conversionGoal: null,
                            filterTestAccounts: values.filterTestAccounts,
                            isPathCleaningEnabled: values.isPathCleaningEnabled,
                            webAnalyticsFilters: values.webAnalyticsFilters,
                        }
                        const [totals, rates] = (await Promise.all([
                            runQuery(
                                'siteTotals',
                                buildSiteTotalsQuery(buildPageDirectoryBaseQuery(filters)),
                                breakpoint
                            ),
                            runQuery(
                                'siteRates',
                                {
                                    ...buildPageDirectoryBaseQuery({ ...filters, compareFilter: { compare: false } }),
                                    pageKeys: [],
                                    metrics: SITE_RATE_METRICS,
                                    sortBy: WebPageDirectorySortBy.TimeOnPage,
                                    includeSiteTotals: true,
                                },
                                breakpoint
                            ),
                        ])) as WebPageDirectoryQueryResponse[]
                        return totals.siteTotals
                            ? {
                                  ...totals.siteTotals,
                                  timeOnPageP90: rates.siteTotals?.timeOnPageP90,
                                  bounceRate: rates.siteTotals?.bounceRate,
                              }
                            : null
                    },
                },
            ],
            aiAssistants: [
                null as AiAssistantRow[] | null,
                {
                    loadAiAssistants: async (_, breakpoint) => {
                        await breakpoint(100)
                        return await run('aiAssistants', breakpoint, (request) =>
                            loadAiAssistantRows(
                                {
                                    window: values.window,
                                    page: props.pageKey,
                                    pathExpr: values.pathExpr,
                                    filterTestAccounts: values.filterTestAccounts,
                                    properties: values.webAnalyticsFilters,
                                },
                                request
                            )
                        )
                    },
                },
            ],
            gscSummary: [
                null as GoogleSearchConsoleSummary | null,
                {
                    loadGscSummary: async (_, breakpoint) => {
                        const query = values.gscSummaryQuery
                        if (!query) {
                            return null
                        }
                        await breakpoint(100)
                        const response = await runQuery('gscSummary', query, breakpoint)
                        const row = response.results?.[0]
                        if (!Array.isArray(row)) {
                            return null
                        }
                        return {
                            clicks: Number(row[0] ?? 0),
                            impressions: Number(row[1] ?? 0),
                            position: row[2] == null ? null : Number(row[2]),
                        }
                    },
                },
            ],
        }
    }),
    selectors({
        baseQuery: [
            (s) => [
                s.dateFilter,
                s.compareFilter,
                s.filterTestAccounts,
                s.isPathCleaningEnabled,
                s.webAnalyticsFilters,
            ],
            (
                dateFilter: DateFilterState,
                compareFilter: CompareFilter,
                filterTestAccounts: boolean,
                isPathCleaningEnabled: boolean,
                webAnalyticsFilters: WebAnalyticsPropertyFilters
            ): WebPageDirectoryQuery =>
                buildPageDirectoryBaseQuery({
                    dateFilter,
                    compareFilter: { ...compareFilter, compare: true },
                    conversionGoal: null,
                    filterTestAccounts,
                    isPathCleaningEnabled,
                    webAnalyticsFilters,
                }),
        ],
        timezone: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): string => currentTeam?.timezone ?? 'UTC',
        ],
        window: [
            (s) => [s.dateFilter, s.timezone],
            (dateFilter: DateFilterState, timezone: string): PagePerformanceWindow =>
                resolvePagePerformanceWindow(dateFilter, { compare: false }, timezone),
        ],
        gscTableName: [
            (s) => [s.dataWarehouseTables],
            (tables: DatabaseSchemaDataWarehouseTable[]): string | null => findGoogleSearchConsoleTable(tables),
        ],
        crawlersMeasured: [
            (s) => [s.siteTotals],
            (siteTotals: WebPageDirectorySiteTotals | null): boolean | null =>
                siteTotals ? areCrawlersMeasured(siteTotals) : null,
        ],
        healthFailed: [
            (s) => [s.failedLoads],
            (failedLoads: Partial<Record<DetailLoad, boolean>>): boolean =>
                !!(failedLoads.pageMetrics || failedLoads.siteTotals),
        ],
        gscSummaryQuery: [
            (s) => [s.gscTableName, s.window, s.isPathCleaningEnabled, s.currentTeam, (_, props) => props.pageKey],
            (
                gscTableName: string | null,
                window: PagePerformanceWindow,
                isPathCleaningEnabled: boolean,
                currentTeam: TeamPublicType | TeamType | null,
                pageKey: string
            ): HogQLQuery | null =>
                gscTableName
                    ? {
                          kind: NodeKind.HogQLQuery,
                          query: buildGoogleSearchConsoleSummaryQuery(
                              gscTableName,
                              pageKey,
                              window,
                              isPathCleaningEnabled,
                              currentTeam?.path_cleaning_filters
                          ),
                          tags: WEB_ANALYTICS_DEFAULT_QUERY_TAGS,
                      }
                    : null,
        ],
        searchConsole: [
            (s) => [s.database, s.databaseLoadError, s.gscTableName, s.gscSummary, s.gscSummaryLoading, s.failedLoads],
            (
                database: DatabaseSchemaQueryResponse | null,
                databaseLoadError: string | null,
                gscTableName: string | null,
                gscSummary: GoogleSearchConsoleSummary | null,
                gscSummaryLoading: boolean,
                failedLoads: Partial<Record<DetailLoad, boolean>>
            ): GoogleSearchConsoleState => {
                if (!database) {
                    return databaseLoadError ? 'error' : 'loading'
                }
                if (!gscTableName) {
                    return 'not_connected'
                }
                if (gscSummaryLoading) {
                    return 'loading'
                }
                if (failedLoads.gscSummary) {
                    return 'error'
                }
                return gscSummary ?? 'not_connected'
            },
        ],
        healthCards: [
            (s) => [s.pageMetrics, s.siteTotals, s.searchConsole, s.pageMetricsLoading, s.siteTotalsLoading],
            (
                pageMetrics: WebPageDirectoryRow | null,
                siteTotals: WebPageDirectorySiteTotals | null,
                searchConsole: GoogleSearchConsoleState,
                pageMetricsLoading: boolean,
                siteTotalsLoading: boolean
            ): PageHealthSummary[] =>
                pageMetricsLoading || siteTotalsLoading
                    ? computePageHealth({ page: null, site: null, searchConsole })
                    : computePageHealth({ page: pageMetrics, site: siteTotals, searchConsole }),
        ],
        pathExpr: [
            (s) => [s.isPathCleaningEnabled, s.currentTeam],
            (isPathCleaningEnabled: boolean, currentTeam: TeamPublicType | TeamType | null): string =>
                buildPagePerformancePathExpr(RAW_PATH, isPathCleaningEnabled, currentTeam?.path_cleaning_filters),
        ],
        aiCrawlersQuery: [
            (s) => [s.window, s.pathExpr, s.filterTestAccounts, s.webAnalyticsFilters, (_, props) => props.pageKey],
            (
                window: PagePerformanceWindow,
                pathExpr: string,
                filterTestAccounts: boolean,
                webAnalyticsFilters: WebAnalyticsPropertyFilters,
                pageKey: string
            ): DataTableNode => ({
                kind: NodeKind.DataTableNode,
                source: {
                    kind: NodeKind.HogQLQuery,
                    query: buildBreakdownQuery('agent_crawls', pageKey, window, pathExpr) ?? '',
                    filters: { filterTestAccounts, properties: webAnalyticsFilters },
                    tags: WEB_ANALYTICS_DEFAULT_QUERY_TAGS,
                },
                embedded: true,
                showActions: false,
            }),
        ],
        tileFilters: [
            (s) => [
                s.dateFilter,
                s.filterTestAccounts,
                s.webAnalyticsFilters,
                s.selectedHost,
                s.isPathCleaningEnabled,
                (_, props) => props.pageUrl,
            ],
            (
                dateFilter: DateFilterState,
                filterTestAccounts: boolean,
                webAnalyticsFilters: WebAnalyticsPropertyFilters,
                selectedHost: string | null,
                isPathCleaningEnabled: boolean,
                pageUrl: string
            ): SearchAndAiTileFilters => ({
                dateFilter,
                filterTestAccounts,
                properties: [
                    ...webAnalyticsFilters,
                    ...createPageReportsFilters(pageUrl, true, selectedHost, isPathCleaningEnabled, true),
                ],
            }),
        ],
        aiReferralTrendQuery: [
            (s) => [s.tileFilters],
            (tileFilters: SearchAndAiTileFilters): InsightVizNode =>
                buildAiReferralTrendQuery(tileFilters, AI_ASSISTANT_BREAKDOWN),
        ],
        aiLandingPagesQuery: [
            (s) => [s.tileFilters, s.compareFilter, s.conversionGoal],
            (
                tileFilters: SearchAndAiTileFilters,
                compareFilter: CompareFilter,
                conversionGoal: WebAnalyticsConversionGoal | null
            ): DataTableNode =>
                buildAiReferralTableQuery(
                    { ...tileFilters, compareFilter, conversionGoal },
                    WebStatsBreakdown.InitialPage
                ),
        ],
        crawlTrendQuery: [
            (s) => [s.tileFilters],
            (tileFilters: SearchAndAiTileFilters): InsightVizNode =>
                buildAiCrawlerTrendQuery(tileFilters, 'AI crawler requests'),
        ],
        googleTrendQuery: [
            (s) => [s.tileFilters],
            (tileFilters: SearchAndAiTileFilters): InsightVizNode => buildGoogleSearchTrendQuery(tileFilters),
        ],
        healthInput: [
            (s) => [s.baseQuery, s.compareFilter],
            (baseQuery: WebPageDirectoryQuery, compareFilter: CompareFilter): string =>
                JSON.stringify([baseQuery, compareFilter]),
        ],
        aiAssistantsInput: [
            (s) => [s.pageReportTab, s.window, s.pathExpr, s.filterTestAccounts, s.webAnalyticsFilters],
            (
                pageReportTab: PageReportTab,
                window: PagePerformanceWindow,
                pathExpr: string,
                filterTestAccounts: boolean,
                webAnalyticsFilters: WebAnalyticsPropertyFilters
            ): string | null =>
                pageReportTab === PageReportTab.AI
                    ? JSON.stringify([window, pathExpr, filterTestAccounts, webAnalyticsFilters])
                    : null,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        hoverHealthCard: ({ card }) => {
            cache.hoveredCards = cache.hoveredCards ?? new Set<string>()
            if (card.status === 'loading' || cache.hoveredCards.has(card.key)) {
                return
            }
            cache.hoveredCards.add(card.key)
            posthog.capture('web analytics page report health card hovered', { card: card.key, status: card.status })
        },
        clickHealthCard: ({ card }) => {
            const destination = HEALTH_CARD_TAB[card.key]
            posthog.capture('web analytics page report health card clicked', {
                card: card.key,
                status: card.status,
                destination_tab: destination,
            })
            actions.setPageReportTab(destination)
        },
        clickSearchConsoleConnect: () => {
            posthog.capture('web analytics page report gsc cta clicked', { location: 'search_tab' })
        },
        clickOpenPage: () => {
            posthog.capture('web analytics page report open page clicked')
        },
        clickHeaderMenuItem: ({ item }) => {
            posthog.capture('web analytics page report menu item clicked', { item })
        },
        reloadHealth: () => {
            if (values.healthFailed) {
                actions.loadPageMetrics(null)
                actions.loadSiteTotals(null)
            }
            if (!values.database) {
                actions.loadDatabase({ shallow: true })
            } else if (values.failedLoads.gscSummary) {
                actions.loadGscSummary(null)
            }
        },
        loadAiAssistantsFailure: () => {
            cache.loadedAiAssistantsInput = null
        },
    })),
    subscriptions(({ actions, cache }) => ({
        healthInput: () => {
            actions.loadPageMetrics(null)
            actions.loadSiteTotals(null)
        },
        gscSummaryQuery: (query: HogQLQuery | null, previousQuery: HogQLQuery | null | undefined) => {
            if (query?.query !== previousQuery?.query || previousQuery === undefined) {
                actions.loadGscSummary(null)
            }
        },
        aiAssistantsInput: (input: string | null) => {
            if (input && input !== cache.loadedAiAssistantsInput) {
                cache.loadedAiAssistantsInput = input
                actions.loadAiAssistants(null)
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (!values.database) {
            actions.loadDatabase({ shallow: true })
        }
    }),
])
