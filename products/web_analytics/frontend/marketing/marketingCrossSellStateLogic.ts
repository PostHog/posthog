export const marketingCrossSellStateLogic: LogicWrapper<marketingCrossSellStateLogicType> =
    kea<marketingCrossSellStateLogicType>([
        props({} as MarketingCrossSellStateLogicProps),
        key(({ teamId }) => teamId),
        path((key) => ['products', 'webAnalytics', 'marketingCrossSellStateLogic', key]),
        connect(() => ({
            values: [teamLogic, ['currentTeam'], featureFlagLogic, ['featureFlags']],
        })),
        actions({
            ensureConnectionState: true,
            snooze: (surface: MarketingCrossSellSurface) => ({ surface, now: Date.now() }),
        }),
        loaders(({ props, values }) => ({
            hasConnectedSources: [
                null as boolean | null,
                {
                    loadConnectionState: async (_: void, breakpoint): Promise<boolean | null> => {
                        const mappings = values.currentTeam?.marketing_analytics_config?.sources_map
                        if (mappings && Object.keys(mappings).length > 0) {
                            return true
                        }
                        const enabledSources = getEnabledNativeMarketingSources(values.featureFlags)
                        let offset = 0
                        while (true) {
                            const page = await externalDataSourcesList(String(props.teamId), {
                                limit: 100,
                                offset,
                            }).catch(() => null)
                            breakpoint()
                            if (!page) {
                                return null
                            }
                            if (
                                page.results.some((source) =>
                                    enabledSources.includes(source.source_type as NativeMarketingSource)
                                )
                            ) {
                                return true
                            }
                            if (!page.next || page.results.length === 0) {
                                return false
                            }
                            offset += page.results.length
                        }
                    },
                },
            ],
        })),
        reducers({
            snoozeState: [
                { dismissedAt: null, dismissCount: 0 } as MarketingCrossSellSnooze,
                { persist: true },
                { snooze: (state, { now }) => snoozeAfterDismissal(state, now) },
            ],
        }),
        selectors({
            isSnoozed: [
                (s) => [s.snoozeState],
                (snoozeState: MarketingCrossSellSnooze): boolean =>
                    isMarketingCrossSellSnoozed(snoozeState, Date.now()),
            ],
        }),
        listeners(({ actions, values, props }) => ({
            ensureConnectionState: () => {
                if (values.hasConnectedSources === null && !values.hasConnectedSourcesLoading) {
                    actions.loadConnectionState()
                }
            },
            snooze: ({ surface }) => {
                captureMarketingCrossSellDismissed(props.teamId, surface, values.snoozeState.dismissCount)
            },
        })),
    ])
