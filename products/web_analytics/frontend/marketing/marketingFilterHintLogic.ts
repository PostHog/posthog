export type marketingFilterHintLogicType = MakeLogicType<
    marketingFilterHintLogicValues,
    marketingFilterHintLogicActions,
    MarketingFilterHintLogicProps,
    marketingFilterHintLogicMeta
>

export const marketingFilterHintLogic: LogicWrapper<marketingFilterHintLogicType> = kea<marketingFilterHintLogicType>([
    props({} as MarketingFilterHintLogicProps),
    key(({ teamId }) => teamId),
    path((key) => ['products', 'webAnalytics', 'marketingFilterHintLogic', key]),
    connect((props: MarketingFilterHintLogicProps) => ({
        values: [
            webAnalyticsLogic,
            ['rawWebAnalyticsFilters', 'dateFilter', 'productTab', 'marketingCrossSellDismissed'],
            marketingCrossSellStateLogic({ teamId: props.teamId }),
            ['hasConnectedSources', 'hasConnectedSourcesLoading', 'isSnoozed'],
            teamLogic,
            ['currentTeam'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [marketingCrossSellStateLogic({ teamId: props.teamId }), ['ensureConnectionState', 'snooze']],
    })),
    actions({
        dismiss: true,
        clickThrough: true,
    }),
    selectors({
        target: [
            (s) => [s.rawWebAnalyticsFilters, s.currentTeam, s.featureFlags],
            (
                filters: WebAnalyticsPropertyFilters,
                currentTeam: TeamPublicType | TeamType | null,
                featureFlags: FeatureFlagsSet
            ): PaidTrafficTarget | null =>
                paidTrafficTargetFromFilters(
                    filters,
                    currentTeam?.marketing_analytics_config,
                    getEnabledNativeMarketingSources(featureFlags)
                ),
        ],
        eligible: [
            (s) => [s.target, s.productTab, s.marketingCrossSellDismissed, s.isSnoozed, s.featureFlags],
            (
                target: PaidTrafficTarget | null,
                productTab: ProductTab,
                marketingCrossSellDismissed: boolean,
                isSnoozed: boolean,
                featureFlags: FeatureFlagsSet
            ): boolean =>
                !!target &&
                productTab === ProductTab.ANALYTICS &&
                !marketingCrossSellDismissed &&
                !isSnoozed &&
                isMarketingCrossSellTestArm(featureFlags),
        ],
        visible: [
            (s) => [s.eligible, s.hasConnectedSources, s.hasConnectedSourcesLoading],
            (eligible: boolean, hasConnectedSources: boolean | null, hasConnectedSourcesLoading: boolean): boolean =>
                eligible && hasConnectedSources !== null && !hasConnectedSourcesLoading,
        ],
        surface: [
            (s) => [s.target],
            (target: PaidTrafficTarget | null): MarketingCrossSellSurface => ({
                variant: 'filter_hint',
                platform: target?.platform ?? null,
            }),
        ],
        destination: [
            (s) => [s.target, s.hasConnectedSources, s.dateFilter, s.featureFlags],
            (
                target: PaidTrafficTarget | null,
                hasConnectedSources: boolean | null,
                dateFilter: DateFilterState,
                featureFlags: FeatureFlagsSet
            ): string =>
                buildMarketingAnalyticsDestination({
                    hasConnectedSources,
                    platform: target?.platform ?? null,
                    dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo },
                    setupEnabled: isMarketingSetupEnabled(featureFlags),
                }),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        dismiss: () => {
            actions.snooze(values.surface)
        },
        clickThrough: () => {
            captureMarketingCrossSellClick(props.teamId, null, values.hasConnectedSources, values.surface)
        },
    })),
    subscriptions(({ actions, values, props }) => ({
        eligible: (eligible: boolean) => {
            if (eligible) {
                actions.ensureConnectionState()
            }
        },
        visible: (visible: boolean) => {
            if (visible) {
                captureMarketingCrossSellShown({
                    teamId: props.teamId,
                    surface: values.surface,
                    hasConnectedSources: values.hasConnectedSources,
                })
            }
        },
    })),
])
