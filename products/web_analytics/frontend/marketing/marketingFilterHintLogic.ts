import { subscriptions } from 'kea-subscriptions'

import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import {
    MarketingCrossSellSurface,
    captureMarketingCrossSellClick,
    captureMarketingCrossSellShown,
} from 'lib/marketingCrossSell'
import { teamLogic } from 'scenes/teamLogic'
import { ProductTab } from 'scenes/web-analytics/common'
import { getEnabledNativeMarketingSources } from 'scenes/web-analytics/tabs/marketing-analytics/frontend/logic/utils'
import { DateFilterState, webAnalyticsLogic } from 'scenes/web-analytics/webAnalyticsLogic'

import { WebAnalyticsPropertyFilters } from '~/queries/schema/schema-general'

import type { FeatureFlagsSet } from '../../../../frontend/src/lib/logic/featureFlagLogic'
import type { TeamPublicType, TeamType } from '../../../../frontend/src/types'
import { marketingCrossSellStateLogic } from './marketingCrossSellStateLogic'
import {
    PaidTrafficTarget,
    buildMarketingAnalyticsDestination,
    isMarketingCrossSellTestArm,
    isMarketingSetupEnabled,
    paidTrafficTargetFromFilters,
} from './marketingCrossSellUtils'

