    currentTeam: TeamPublicType | TeamType | null // teamLogic
    dateFilter: DateFilterState // webAnalyticsLogic
    marketingCrossSellDismissed: boolean // webAnalyticsLogic
    productTab: ProductTab // webAnalyticsLogic
    rawWebAnalyticsFilters: WebAnalyticsPropertyFilters // webAnalyticsLogic
    destination: string
