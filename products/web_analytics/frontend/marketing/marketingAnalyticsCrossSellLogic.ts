function loadConnectionsIfNeeded({ values, actions }: marketingAnalyticsCrossSellLogicType): void {
    if (values.hasPaidTraffic && values.hasConnectedSources === null && !values.hasConnectedSourcesLoading) {
        actions.loadConnectionState()
    }
}

export const marketingAnalyticsCrossSellLogic: LogicWrapper<marketingAnalyticsCrossSellLogicType> =
    kea<marketingAnalyticsCrossSellLogicType>([
        props({} as MarketingAnalyticsCrossSellLogicProps),
        key(({ teamId, channels }) => `${teamId}:${channels.key}`),
        path((key) => ['products', 'webAnalytics', 'marketingAnalyticsCrossSellLogic', key]),
        connect((props: MarketingAnalyticsCrossSellLogicProps) => ({
            values: [
                dataNodeLogic(props.channels),
                ['response', 'responseLoading', 'responseError'],
                teamLogic,
                ['currentTeam'],
                featureFlagLogic,
                ['featureFlags'],
            ],
            actions: [dataNodeLogic(props.channels), ['loadDataSuccess']],
        })),
        loaders(({ props, values }) => ({
            hasConnectedSources: [
                null as boolean | null,
                {
                    loadConnectionState: async (_: void, breakpoint): Promise<boolean | null> => {
                        const mappings = values.currentTeam?.marketing_analytics_config?.sources_map
                        if (mappings && Object.keys(mappings).length > 0) {
                            return true
                        }
                        const enabledSources = getEnabledNativeMarketingSources(values.featureFlags)
                        let offset = 0
                        while (true) {
                            const page = await externalDataSourcesList(String(props.teamId), {
                                limit: 100,
                                offset,
                            }).catch(() => null)
                            breakpoint()
                            if (!page) {
                                return null
                            }
                            if (
                                page.results.some((source) =>
                                    enabledSources.includes(source.source_type as NativeMarketingSource)
                                )
                            ) {
                                return true
                            }
                            if (!page.next || page.results.length === 0) {
                                return false
                            }
                            offset += page.results.length
                        }
                    },
                },
            ],
        })),
        selectors({
            hasPaidTraffic: [
                (s) => [s.response, s.responseLoading, s.responseError],
                (
                    response:
                        | ErrorTrackingQueryResponse
                        | HogQLAutocompleteResponse
                        | HogQLMetadataResponse
                        | HogQLQueryResponse<any[]>
                        | HogQueryResponse
                        | LogAttributesQueryResponse
                        | LogValuesQueryResponse
                        | MetricsQueryResponse
                        | Record<string, any>
                        | SessionsQueryResponse
                        | TraceSpansAggregationQueryResponse
                        | TraceSpansAttributeBreakdownQueryResponse
                        | TraceSpansQueryResponse
                        | TraceSpansTreeQueryResponse
                        | null,
                    loading: boolean,
                    error: string | null
                ): boolean =>
                    !loading && !error && hasPaidChannelTraffic(response as WebStatsTableQueryResponse | null),
            ],
            destination: [
                (s) => [s.hasConnectedSources, s.featureFlags, (_, props) => props.channels.query],
                (hasConnectedSources: boolean | null, featureFlags: FeatureFlagsSet, query): string => {
                    const params = new URLSearchParams()
                    if ('dateRange' in query && query.dateRange) {
                        if (query.dateRange.date_from) {
                            params.set('date_from', query.dateRange.date_from)
                        }
                        // An empty value marks an open-ended range, so Marketing analytics drops a saved end date.
                        params.set('date_to', query.dateRange.date_to ?? '')
                    }
                    if (
                        !hasConnectedSources &&
                        (featureFlags[FEATURE_FLAGS.MARKETING_ANALYTICS_SETUP] ||
                            featureFlags[FEATURE_FLAGS.MARKETING_ANALYTICS_NEW_DASHBOARD])
                    ) {
                        params.set('tab', 'setup')
                        params.set('section', 'sources')
                    }
                    return `${urls.marketingAnalyticsApp()}?${params.toString()}`
                },
            ],
        }),
        listeners((logic) => ({
            loadDataSuccess: () => loadConnectionsIfNeeded(logic),
        })),
        propsChanged(({ props }) => {
            // The Channels table is unmounted on UTM tabs, so it cannot update this shared node.
            dataNodeLogic(props.channels)
        }),
        afterMount(loadConnectionsIfNeeded),
    ])
