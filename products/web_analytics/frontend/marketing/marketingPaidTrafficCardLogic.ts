export const marketingPaidTrafficCardLogic: LogicWrapper<marketingPaidTrafficCardLogicType> =
    kea<marketingPaidTrafficCardLogicType>([
        props({} as MarketingPaidTrafficCardLogicProps),
        key(({ teamId, utmSources }) => `${teamId}:${utmSources.key}`),
        path((key) => ['products', 'webAnalytics', 'marketingPaidTrafficCardLogic', key]),
        connect((props: MarketingPaidTrafficCardLogicProps) => ({
            values: [
                marketingAnalyticsCrossSellLogic({ teamId: props.teamId, channels: props.channels }),
                ['paidTraffic', 'dateRange', 'hasConnectedSources'],
                dataNodeLogic(props.utmSources),
                ['response', 'responseLoading', 'responseError'],
                teamLogic,
                ['currentTeam'],
                featureFlagLogic,
                ['featureFlags'],
            ],
            actions: [
                marketingAnalyticsCrossSellLogic({ teamId: props.teamId, channels: props.channels }),
                ['dismissCard'],
            ],
        })),
        actions({
            clickThrough: (breakdown: WebStatsBreakdown, platform: NativeMarketingSource | null) => ({
                breakdown,
                platform,
            }),
        }),
        selectors({
            platformsResolved: [
                (s) => [s.response, s.responseLoading, s.responseError],
                (
                    response:
                        | ErrorTrackingQueryResponse
                        | HogQLAutocompleteResponse
                        | HogQLMetadataResponse
                        | HogQLQueryResponse<any[]>
                        | HogQueryResponse
                        | LogAttributesQueryResponse
                        | LogValuesQueryResponse
                        | MetricsQueryResponse
                        | Record<string, any>
                        | SessionsQueryResponse
                        | TraceSpansAggregationQueryResponse
                        | TraceSpansAttributeBreakdownQueryResponse
                        | TraceSpansQueryResponse
                        | TraceSpansTreeQueryResponse
                        | null,
                    loading: boolean,
                    error: string | null
                ): boolean => !loading && (response !== null || error !== null),
            ],
            platforms: [
                (s) => [s.platformsResolved, s.response, s.responseError, s.currentTeam, s.featureFlags],
                (
                    platformsResolved: boolean,
                    response:
                        | ErrorTrackingQueryResponse
                        | HogQLAutocompleteResponse
                        | HogQLMetadataResponse
                        | HogQLQueryResponse<any[]>
                        | HogQueryResponse
                        | LogAttributesQueryResponse
                        | LogValuesQueryResponse
                        | MetricsQueryResponse
                        | Record<string, any>
                        | SessionsQueryResponse
                        | TraceSpansAggregationQueryResponse
                        | TraceSpansAttributeBreakdownQueryResponse
                        | TraceSpansQueryResponse
                        | TraceSpansTreeQueryResponse
                        | null,
                    error: string | null,
                    currentTeam: TeamPublicType | TeamType | null,
                    featureFlags: FeatureFlagsSet
                ) =>
                    platformsResolved && !error
                        ? detectAdPlatforms(
                              response as WebStatsTableQueryResponse | null,
                              currentTeam?.marketing_analytics_config,
                              getEnabledNativeMarketingSources(featureFlags)
                          )
                        : ([] as NativeMarketingSource[]),
            ],
            primaryPlatform: [
                (s) => [s.platforms],
                (platforms: NativeMarketingSource[]): NativeMarketingSource | null => platforms[0] ?? null,
            ],
            setupEnabled: [
                (s) => [s.featureFlags],
                (featureFlags: FeatureFlagsSet): boolean => isMarketingSetupEnabled(featureFlags),
            ],
            platformDestination: [
                (s) => [s.primaryPlatform, s.dateRange, s.setupEnabled],
                (
                    primaryPlatform:
                        | 'AmazonAds'
                        | 'AppleSearchAds'
                        | 'BingAds'
                        | 'GoogleAds'
                        | 'LinkedinAds'
                        | 'MetaAds'
                        | 'OpenAIAds'
                        | 'PinterestAds'
                        | 'RedditAds'
                        | 'RoktAds'
                        | 'SnapchatAds'
                        | 'TikTokAds'
                        | 'TwitterAds'
                        | null,
                    dateRange: DateRange | null,
                    setupEnabled: boolean
                ): string =>
                    buildMarketingAnalyticsDestination({
                        hasConnectedSources: false,
                        platform: primaryPlatform,
                        dateRange,
                        setupEnabled,
                    }),
            ],
            allPlatformsDestination: [
                (s) => [s.dateRange, s.setupEnabled],
                (dateRange: DateRange | null, setupEnabled: boolean): string =>
                    buildMarketingAnalyticsDestination({
                        hasConnectedSources: false,
                        platform: null,
                        dateRange,
                        setupEnabled,
                    }),
            ],
        }),
        listeners(({ values, props }) => ({
            clickThrough: ({ breakdown, platform }) => {
                captureMarketingCrossSellClick(props.teamId, breakdown, values.hasConnectedSources, {
                    variant: 'quantified_card',
                    platform,
                })
            },
        })),
        subscriptions(({ values, props }) => ({
            platformsResolved: (platformsResolved: boolean) => {
                if (!platformsResolved) {
                    return
                }
                captureMarketingCrossSellShown({
                    teamId: props.teamId,
                    surface: { variant: 'quantified_card', platform: values.primaryPlatform },
                    hasConnectedSources: values.hasConnectedSources,
                    paidVisitors: values.paidTraffic?.paidVisitors,
                    paidShare: values.paidTraffic?.share,
                    platforms: values.platforms,
                })
            },
        })),
    ])
