export const partnerBillingLogic: LogicWrapper<partnerBillingLogicType> = kea<partnerBillingLogicType>([
    props({} as PartnerBillingLogicProps),
    key((props) => props.applicationId),
    path((key) => ['products', 'billing', 'frontend', 'partnerBilling', 'partnerBillingLogic', key]),
    connect(() => ({
        values: [organizationLogic, ['currentOrganizationId'], billingLogic, ['billing', 'billingLoading']],
    })),
    actions({
        payerSaved: (payer: PartnerPayerStatusApi) => ({ payer }),
        dismissWebhookSecret: true,
        saveSpendingSettings: true,
    }),
    loaders(({ props, values }) => ({
        payer: [
            null as PartnerPayerStatusApi | null,
            {
                loadPartnerBillingPayer: async () => {
                    return await api.partnerBillingRetrieve(values.currentOrganizationId, props.applicationId)
                },
            },
        ],
        billingPortal: [
            null as PartnerPayerPortalApi | null,
            {
                openPartnerBillingPortal: async () => {
                    return await api.partnerBillingPortalCreate(values.currentOrganizationId, props.applicationId, {
                        return_path: urls.settings('organization-partner-billing'),
                    })
                },
            },
        ],
        webhookSecret: [
            null as PartnerPayerWebhookSecretApi | null,
            {
                rotatePartnerBillingWebhookSecret: async () => {
                    return await api.partnerBillingWebhookSecretCreate(
                        values.currentOrganizationId,
                        props.applicationId
                    )
                },
            },
        ],
        testEvent: [
            null as PartnerPayerTestEventApi | null,
            {
                sendPartnerBillingTestEvent: async () => {
                    return await api.partnerBillingTestEventCreate(values.currentOrganizationId, props.applicationId)
                },
            },
        ],
    })),
    reducers({
        payer: {
            payerSaved: (_, { payer }) => payer,
            rotatePartnerBillingWebhookSecretSuccess: (payer, { webhookSecret }) =>
                payer && webhookSecret
                    ? { ...payer, webhook: { ...payer.webhook, secret_created_at: webhookSecret.created_at } }
                    : payer,
        },
        payerError: [
            null as string | null,
            {
                loadPartnerBillingPayer: () => null,
                loadPartnerBillingPayerSuccess: () => null,
                loadPartnerBillingPayerFailure: (_, { errorObject }) => partnerBillingErrorMessage(errorObject),
            },
        ],
        webhookSecret: {
            dismissWebhookSecret: () => null,
        },
    }),
    forms(({ actions, props, values }) => ({
        webhookForm: {
            defaults: webhookFormValues(null) as PartnerBillingWebhookFormValues,
            errors: ({ webhook_url }) => ({
                webhook_url: webhookUrlError(webhook_url),
            }),
            submit: async (form) => {
                const payer = await api.partnerBillingPartialUpdate(
                    values.currentOrganizationId,
                    props.applicationId,
                    webhookChanges(values.payer, form)
                )
                actions.payerSaved(payer)
            },
        },
        spendingForm: {
            defaults: spendingFormValues(null) as PartnerBillingSpendingFormValues,
            errors: ({ spend_alert_usd, spend_cap_usd, default_limits_usd }) => ({
                spend_alert_usd: dollarAmountError(spend_alert_usd),
                spend_cap_usd: dollarAmountError(spend_cap_usd),
                default_limits_usd: limitErrors(default_limits_usd),
            }),
            submit: async (form) => {
                const payer = await api.partnerBillingPartialUpdate(
                    values.currentOrganizationId,
                    props.applicationId,
                    spendingChanges(values.payer, form)
                )
                actions.payerSaved(payer)
            },
        },
    })),
    selectors({
        limitCatalog: [
            (s) => [s.billing],
            (billing: BillingType | null): PartnerBillingLimitProduct[] =>
                limitCatalogFromBillingProducts(billing?.products ?? []),
        ],
        limitProductNames: [
            (s) => [s.limitCatalog],
            (limitCatalog: PartnerBillingLimitProduct[]): Record<string, string> =>
                Object.fromEntries(limitCatalog.map((product) => [product.key, product.name])),
        ],
        defaultLimitProducts: [
            (s) => [s.limitCatalog, s.payer],
            (
                limitCatalog: PartnerBillingLimitProduct[],
                payer: PartnerPayerStatusApi | null
            ): PartnerBillingLimitProduct[] =>
                limitProductsFor(limitCatalog, limitFormValues(payer?.default_limits_usd)),
        ],
        webhookFormHasChanges: [
            (s) => [s.payer, s.webhookForm],
            (payer: PartnerPayerStatusApi | null, webhookForm: PartnerBillingWebhookFormValues): boolean =>
                Object.keys(webhookChanges(payer, webhookForm)).length > 0,
        ],
        spendingFormHasChanges: [
            (s) => [s.payer, s.spendingForm],
            (payer: PartnerPayerStatusApi | null, spendingForm: PartnerBillingSpendingFormValues): boolean =>
                Object.keys(spendingChanges(payer, spendingForm)).length > 0,
        ],
        spendingFormChangesDefaultLimits: [
            (s) => [s.payer, s.spendingForm],
            (payer: PartnerPayerStatusApi | null, spendingForm: PartnerBillingSpendingFormValues): boolean =>
                'default_limits_usd' in spendingChanges(payer, spendingForm),
        ],
    }),
    listeners(({ actions, values }) => ({
        loadPartnerBillingPayerSuccess: ({ payer }) => {
            // A reload must not wipe what someone typed and has not saved yet.
            if (!values.webhookFormChanged) {
                actions.resetWebhookForm(webhookFormValues(payer))
            }
            if (!values.spendingFormChanged) {
                actions.resetSpendingForm(spendingFormValues(payer))
            }
        },
        saveSpendingSettings: () => {
            // Submitting a form with errors only shows the errors, so it needs no confirmation.
            if (!values.spendingFormChangesDefaultLimits || values.spendingFormHasErrors) {
                actions.submitSpendingForm()
                return
            }
            LemonDialog.open({
                title: 'Change your default limits?',
                description:
                    "Default limits apply to every organization you pay for that doesn't have its own limit for that product, including organizations you already pay for.",
                primaryButton: {
                    children: 'Save spending settings',
                    onClick: () => actions.submitSpendingForm(),
                    'data-attr': 'partner-billing-confirm-default-limits',
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        submitWebhookFormSuccess: () => {
            actions.resetWebhookForm(webhookFormValues(values.payer))
            lemonToast.success('Webhook URL saved.')
        },
        submitWebhookFormFailure: ({ error }) => {
            const fieldError = partnerBillingFieldError(error, 'webhook_url')
            if (fieldError) {
                actions.setWebhookFormManualErrors({ webhook_url: fieldError })
            } else if (error instanceof ApiError) {
                lemonToast.error(`Couldn't save the webhook URL. ${partnerBillingErrorMessage(error)}`)
            }
        },
        submitSpendingFormSuccess: () => {
            actions.resetSpendingForm(spendingFormValues(values.payer))
            lemonToast.success('Spending settings saved.')
        },
        submitSpendingFormFailure: ({ error }) => {
            const fieldName = ['spend_alert_usd', 'spend_cap_usd'].find((field) =>
                partnerBillingFieldError(error, field)
            )
            if (fieldName) {
                actions.setSpendingFormManualErrors({ [fieldName]: partnerBillingFieldError(error, fieldName) })
            } else if (error instanceof ApiError) {
                lemonToast.error(`Couldn't save the spending settings. ${partnerBillingErrorMessage(error)}`)
            }
        },
        openPartnerBillingPortalSuccess: ({ billingPortal }) => {
            if (billingPortal) {
                window.location.assign(billingPortal.url)
            }
        },
        openPartnerBillingPortalFailure: ({ errorObject }) => {
            lemonToast.error(`Couldn't open the billing portal. ${partnerBillingErrorMessage(errorObject)}`)
        },
        rotatePartnerBillingWebhookSecretFailure: ({ errorObject }) => {
            lemonToast.error(`Couldn't create a signing secret. ${partnerBillingErrorMessage(errorObject)}`)
        },
        sendPartnerBillingTestEventSuccess: ({ testEvent }) => {
            if (testEvent) {
                lemonToast.success(`Test event sent. Look for event ${testEvent.event_id} at your webhook URL.`)
            }
        },
        sendPartnerBillingTestEventFailure: ({ errorObject }) => {
            lemonToast.error(`Couldn't send the test event. ${partnerBillingErrorMessage(errorObject)}`)
        },
    })),
    afterMount(({ actions }) => {
        actions.loadPartnerBillingPayer()
    }),
])
