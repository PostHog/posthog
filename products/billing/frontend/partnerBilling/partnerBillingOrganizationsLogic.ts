export const partnerBillingOrganizationsLogic: LogicWrapper<partnerBillingOrganizationsLogicType> =
    kea<partnerBillingOrganizationsLogicType>([
        props({} as PartnerBillingLogicProps),
        key((props) => props.applicationId),
        path((key) => ['products', 'billing', 'frontend', 'partnerBilling', 'partnerBillingOrganizationsLogic', key]),
        connect((props: PartnerBillingLogicProps) => ({
            values: [organizationLogic, ['currentOrganizationId'], partnerBillingLogic(props), ['limitCatalog']],
        })),
        actions({
            setOrganizationsPage: (page: number) => ({ page }),
            openOrganizationLimits: (organization: PartnerPayerOrganizationApi) => ({ organization }),
            closeOrganizationLimits: true,
            organizationLimitsSaved: (organization: PartnerPayerOrganizationApi) => ({ organization }),
        }),
        loaders(({ props, values }) => ({
            organizations: [
                null as PartnerPayerOrganizationListApi | null,
                {
                    loadPartnerBillingOrganizations: async (_ = undefined, breakpoint) => {
                        const organizations = await api.partnerBillingOrganizationList(
                            values.currentOrganizationId,
                            props.applicationId,
                            partnerBillingPageParams(values.organizationsPage)
                        )
                        breakpoint()
                        return organizations
                    },
                },
            ],
        })),
        reducers({
            organizationsPage: [
                1,
                {
                    setOrganizationsPage: (_, { page }) => page,
                },
            ],
            organizations: {
                organizationLimitsSaved: (state, { organization }) =>
                    state && {
                        ...state,
                        results: state.results.map((row) =>
                            row.organization_id === organization.organization_id ? organization : row
                        ),
                    },
            },
            organizationsError: [
                null as string | null,
                {
                    loadPartnerBillingOrganizations: () => null,
                    loadPartnerBillingOrganizationsSuccess: () => null,
                    loadPartnerBillingOrganizationsFailure: (_, { errorObject }) =>
                        partnerBillingErrorMessage(errorObject),
                },
            ],
            // Invoices name the organization only by ID, so names collect here as pages load.
            organizationNames: [
                {} as Record<string, string>,
                {
                    loadPartnerBillingOrganizationsSuccess: (state, { organizations }) => ({
                        ...state,
                        ...Object.fromEntries(
                            (organizations?.results ?? [])
                                .filter((organization) => !!organization.name)
                                .map((organization) => [organization.organization_id, organization.name as string])
                        ),
                    }),
                },
            ],
            editingOrganization: [
                null as PartnerPayerOrganizationApi | null,
                {
                    openOrganizationLimits: (_, { organization }) => organization,
                    closeOrganizationLimits: () => null,
                    organizationLimitsSaved: () => null,
                },
            ],
        }),
        forms(({ actions, props, values }) => ({
            organizationLimitsForm: {
                defaults: { custom_limits_usd: {} } as PartnerBillingOrganizationLimitsFormValues,
                errors: ({ custom_limits_usd }) => ({
                    custom_limits_usd: limitErrors(custom_limits_usd),
                }),
                submit: async ({ custom_limits_usd }) => {
                    const organization = values.editingOrganization
                    if (!organization) {
                        return
                    }
                    const saved = await api.partnerBillingOrganizationLimitsPartialUpdate(
                        values.currentOrganizationId,
                        props.applicationId,
                        organization.organization_id,
                        { custom_limits_usd: limitChanges(organization.custom_limits_usd, custom_limits_usd) }
                    )
                    actions.organizationLimitsSaved(saved)
                },
            },
        })),
        selectors({
            editingLimitProducts: [
                (s) => [s.limitCatalog, s.editingOrganization],
                (
                    limitCatalog: PartnerBillingLimitProduct[],
                    editingOrganization: PartnerPayerOrganizationApi | null
                ): PartnerBillingLimitProduct[] =>
                    limitProductsFor(limitCatalog, limitFormValues(editingOrganization?.custom_limits_usd)),
            ],
            organizationLimitsFormHasChanges: [
                (s) => [s.editingOrganization, s.organizationLimitsForm],
                (
                    editingOrganization: PartnerPayerOrganizationApi | null,
                    organizationLimitsForm: PartnerBillingOrganizationLimitsFormValues
                ): boolean =>
                    Object.keys(
                        limitChanges(editingOrganization?.custom_limits_usd, organizationLimitsForm.custom_limits_usd)
                    ).length > 0,
            ],
        }),
        listeners(({ actions }) => ({
            setOrganizationsPage: () => {
                actions.loadPartnerBillingOrganizations()
            },
            openOrganizationLimits: ({ organization }) => {
                actions.resetOrganizationLimitsForm({
                    custom_limits_usd: limitFormValues(organization.custom_limits_usd),
                })
            },
            organizationLimitsSaved: ({ organization }) => {
                lemonToast.success(`Limits saved for ${organization.name ?? organization.organization_id}.`)
            },
            submitOrganizationLimitsFormFailure: ({ error }) => {
                if (error instanceof ApiError) {
                    lemonToast.error(`Couldn't save the limits. ${partnerBillingErrorMessage(error)}`)
                }
            },
        })),
        afterMount(({ actions }) => {
            actions.loadPartnerBillingOrganizations()
        }),
    ])
