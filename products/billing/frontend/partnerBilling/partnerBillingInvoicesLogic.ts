import {
    MakeLogicType,
    LogicWrapper,
    actions,
    afterMount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
} from 'kea'
import { loaders } from 'kea-loaders'

import { organizationLogic } from 'scenes/organizationLogic'

import * as api from '../generated/api'
import type { PartnerBillingInvoicesListStatus, PartnerPayerInvoiceListApi } from '../generated/api.schemas'
import { partnerBillingErrorMessage } from './partnerBillingErrors'
import type { PartnerBillingLogicProps } from './partnerBillingLogic'
import { partnerBillingPageParams } from './partnerBillingPagination'

export const PARTNER_BILLING_INVOICES_ELEMENT_ID = 'partner-billing-invoices'

export interface PartnerBillingInvoiceOrganizationFilter {
    organizationId: string
    name: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface partnerBillingInvoicesLogicValues {
    currentOrganizationId: string // organizationLogic
    invoiceOrganizationFilter: PartnerBillingInvoiceOrganizationFilter | null
    invoiceStatusFilter: PartnerBillingInvoicesListStatus | null
    invoices: PartnerPayerInvoiceListApi | null
    invoicesError: string | null
    invoicesLoading: boolean
    invoicesPage: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface partnerBillingInvoicesLogicActions {
    loadPartnerBillingInvoices: (_?: any) => any
    loadPartnerBillingInvoicesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadPartnerBillingInvoicesSuccess: (
        invoices: PartnerPayerInvoiceListApi,
        payload?: any
    ) => {
        invoices: PartnerPayerInvoiceListApi
        payload?: any
    }
    setInvoiceOrganizationFilter: (organization: PartnerBillingInvoiceOrganizationFilter | null) => {
        organization: PartnerBillingInvoiceOrganizationFilter | null
    }
    setInvoiceStatusFilter: (status: PartnerBillingInvoicesListStatus | null) => {
        status: PartnerBillingInvoicesListStatus | null
    }
    setInvoicesPage: (page: number) => {
        page: number
    }
    showOrganizationInvoices: (organization: PartnerBillingInvoiceOrganizationFilter) => {
        organization: PartnerBillingInvoiceOrganizationFilter
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface partnerBillingInvoicesLogicMeta {
    key: string
}

export type partnerBillingInvoicesLogicType = MakeLogicType<
    partnerBillingInvoicesLogicValues,
    partnerBillingInvoicesLogicActions,
    PartnerBillingLogicProps,
    partnerBillingInvoicesLogicMeta
>

export const partnerBillingInvoicesLogic: LogicWrapper<partnerBillingInvoicesLogicType> =
    kea<partnerBillingInvoicesLogicType>([
        props({} as PartnerBillingLogicProps),
        key((props) => props.applicationId),
        path((key) => ['products', 'billing', 'frontend', 'partnerBilling', 'partnerBillingInvoicesLogic', key]),
        connect(() => ({
            values: [organizationLogic, ['currentOrganizationId']],
        })),
        actions({
            setInvoicesPage: (page: number) => ({ page }),
            setInvoiceStatusFilter: (status: PartnerBillingInvoicesListStatus | null) => ({ status }),
            setInvoiceOrganizationFilter: (organization: PartnerBillingInvoiceOrganizationFilter | null) => ({
                organization,
            }),
            showOrganizationInvoices: (organization: PartnerBillingInvoiceOrganizationFilter) => ({ organization }),
        }),
        loaders(({ props, values }) => ({
            invoices: [
                null as PartnerPayerInvoiceListApi | null,
                {
                    loadPartnerBillingInvoices: async (_ = undefined, breakpoint) => {
                        const invoices = await api.partnerBillingInvoicesList(
                            values.currentOrganizationId,
                            props.applicationId,
                            {
                                ...partnerBillingPageParams(values.invoicesPage),
                                organization_id: values.invoiceOrganizationFilter?.organizationId,
                                status: values.invoiceStatusFilter ?? undefined,
                            }
                        )
                        breakpoint()
                        return invoices
                    },
                },
            ],
        })),
        reducers({
            invoicesPage: [
                1,
                {
                    setInvoicesPage: (_, { page }) => page,
                    setInvoiceStatusFilter: () => 1,
                    setInvoiceOrganizationFilter: () => 1,
                },
            ],
            invoiceStatusFilter: [
                null as PartnerBillingInvoicesListStatus | null,
                {
                    setInvoiceStatusFilter: (_, { status }) => status,
                },
            ],
            invoiceOrganizationFilter: [
                null as PartnerBillingInvoiceOrganizationFilter | null,
                {
                    setInvoiceOrganizationFilter: (_, { organization }) => organization,
                },
            ],
            invoicesError: [
                null as string | null,
                {
                    loadPartnerBillingInvoices: () => null,
                    loadPartnerBillingInvoicesSuccess: () => null,
                    loadPartnerBillingInvoicesFailure: (_, { errorObject }) => partnerBillingErrorMessage(errorObject),
                },
            ],
        }),
        listeners(({ actions }) => ({
            setInvoicesPage: () => {
                actions.loadPartnerBillingInvoices()
            },
            setInvoiceStatusFilter: () => {
                actions.loadPartnerBillingInvoices()
            },
            setInvoiceOrganizationFilter: () => {
                actions.loadPartnerBillingInvoices()
            },
            showOrganizationInvoices: ({ organization }) => {
                actions.setInvoiceOrganizationFilter(organization)
                document
                    .getElementById(PARTNER_BILLING_INVOICES_ELEMENT_ID)
                    ?.scrollIntoView({ behavior: 'smooth', block: 'start' })
            },
        })),
        afterMount(({ actions }) => {
            actions.loadPartnerBillingInvoices()
        }),
    ])
