export const partnerBillingSettlementsLogic: LogicWrapper<partnerBillingSettlementsLogicType> =
    kea<partnerBillingSettlementsLogicType>([
        props({} as PartnerBillingLogicProps),
        key((props) => props.applicationId),
        path((key) => ['products', 'billing', 'frontend', 'partnerBilling', 'partnerBillingSettlementsLogic', key]),
        connect((props: PartnerBillingLogicProps) => ({
            values: [organizationLogic, ['currentOrganizationId']],
            actions: [partnerBillingLogic(props), ['loadPartnerBillingPayer']],
        })),
        actions({
            setSettlementsPage: (page: number) => ({ page }),
            openSettlement: (settlementId: string) => ({ settlementId }),
            closeSettlement: true,
            retrySettlement: (settlement: PartnerPayerSettlementApi) => ({ settlement }),
        }),
        loaders(({ props, values }) => ({
            settlements: [
                null as PartnerPayerSettlementListApi | null,
                {
                    loadPartnerBillingSettlements: async (_ = undefined, breakpoint) => {
                        const settlements = await api.partnerBillingSettlementsList(
                            values.currentOrganizationId,
                            props.applicationId,
                            partnerBillingPageParams(values.settlementsPage)
                        )
                        breakpoint()
                        return settlements
                    },
                },
            ],
            openedSettlement: [
                null as PartnerPayerSettlementDetailApi | null,
                {
                    loadPartnerBillingSettlement: async ({ settlementId }: { settlementId: string }, breakpoint) => {
                        const settlement = await api.partnerBillingSettlementsRetrieve(
                            values.currentOrganizationId,
                            props.applicationId,
                            settlementId
                        )
                        breakpoint()
                        return settlement
                    },
                },
            ],
            retriedSettlement: [
                null as PartnerPayerSettlementApi | null,
                {
                    retryPartnerBillingSettlement: async ({ settlementId }: { settlementId: string }) => {
                        return await api.partnerBillingSettlementRetryCreate(
                            values.currentOrganizationId,
                            props.applicationId,
                            settlementId
                        )
                    },
                },
            ],
        })),
        reducers({
            settlementsPage: [
                1,
                {
                    setSettlementsPage: (_, { page }) => page,
                },
            ],
            settlementsError: [
                null as string | null,
                {
                    loadPartnerBillingSettlements: () => null,
                    loadPartnerBillingSettlementsSuccess: () => null,
                    loadPartnerBillingSettlementsFailure: (_, { errorObject }) =>
                        partnerBillingErrorMessage(errorObject),
                },
            ],
            openedSettlementId: [
                null as string | null,
                {
                    openSettlement: (_, { settlementId }) => settlementId,
                    closeSettlement: () => null,
                },
            ],
            openedSettlement: {
                openSettlement: () => null,
                closeSettlement: () => null,
                retryPartnerBillingSettlementSuccess: (state, { retriedSettlement }) =>
                    state && retriedSettlement?.settlement_id === state.settlement_id
                        ? { ...state, ...retriedSettlement }
                        : state,
            },
            openedSettlementError: [
                null as string | null,
                {
                    loadPartnerBillingSettlement: () => null,
                    loadPartnerBillingSettlementSuccess: () => null,
                    loadPartnerBillingSettlementFailure: (_, { errorObject }) =>
                        partnerBillingErrorMessage(errorObject),
                },
            ],
            settlements: {
                retryPartnerBillingSettlementSuccess: (state, { retriedSettlement }) =>
                    state && retriedSettlement
                        ? {
                              ...state,
                              results: state.results.map((settlement) =>
                                  settlement.settlement_id === retriedSettlement.settlement_id
                                      ? retriedSettlement
                                      : settlement
                              ),
                          }
                        : state,
            },
            retryingSettlementId: [
                null as string | null,
                {
                    retryPartnerBillingSettlement: (_, { settlementId }) => settlementId,
                    retryPartnerBillingSettlementSuccess: () => null,
                    retryPartnerBillingSettlementFailure: () => null,
                },
            ],
        }),
        listeners(({ actions }) => ({
            setSettlementsPage: () => {
                actions.loadPartnerBillingSettlements()
            },
            openSettlement: ({ settlementId }) => {
                actions.loadPartnerBillingSettlement({ settlementId })
            },
            retrySettlement: ({ settlement }) => {
                if (isRetryableSettlement(settlement)) {
                    actions.retryPartnerBillingSettlement({ settlementId: settlement.settlement_id })
                }
            },
            retryPartnerBillingSettlementSuccess: ({ retriedSettlement }) => {
                if (retriedSettlement?.status === 'paid') {
                    lemonToast.success('Charge succeeded.')
                } else if (retriedSettlement && isRetryableSettlement(retriedSettlement)) {
                    lemonToast.error('The charge failed again. Update your payment details, then retry the charge.')
                } else {
                    lemonToast.info('Billing is processing the charge. Reload this page later to see the result.')
                }
                // Paying a failed settlement can clear the past-due warning at the top of the page.
                actions.loadPartnerBillingPayer()
            },
            retryPartnerBillingSettlementFailure: ({ errorObject }) => {
                lemonToast.error(`Couldn't retry the charge. ${partnerBillingErrorMessage(errorObject)}`)
            },
        })),
        afterMount(({ actions }) => {
            actions.loadPartnerBillingSettlements()
        }),
    ])
