export const metricsDashboardReviewSceneLogic = kea<metricsDashboardReviewSceneLogicType>([
    path(['products', 'metrics', 'frontend', 'dashboardReview', 'metricsDashboardReviewSceneLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        setStatusFilter: (statusFilter: ReviewStatusFilter) => ({ statusFilter }),
        setTemplateId: (templateId: string | null) => ({ templateId }),
        setPreviewError: (previewError: string | null) => ({ previewError }),
        analyzeProject: true,
    }),
    loaders(({ values }) => ({
        templates: [
            null as MetricsDashboardTemplateApi[] | null,
            {
                loadTemplates: async () =>
                    metricsDashboardTemplatesList(
                        String(values.currentTeamId),
                        values.statusFilter === 'all' ? {} : { status: values.statusFilter }
                    ),
            },
        ],
        template: [
            null as MetricsDashboardTemplateApi | null,
            {
                loadTemplate: async () =>
                    values.templateId
                        ? metricsDashboardTemplatesRetrieve(String(values.currentTeamId), values.templateId)
                        : null,
                approveTemplate: async () => {
                    try {
                        const template = await metricsDashboardTemplatesApproveCreate(
                            String(values.currentTeamId),
                            values.templateId as string
                        )
                        lemonToast.success(`Approved. Projects that send these metrics now see "${template.name}".`)
                        return template
                    } catch (error) {
                        lemonToast.error(errorDetail(error, 'Could not approve the dashboard.'))
                        return values.template
                    }
                },
                rejectTemplate: async () => {
                    try {
                        const template = await metricsDashboardTemplatesRejectCreate(
                            String(values.currentTeamId),
                            values.templateId as string
                        )
                        lemonToast.info(`Rejected "${template.name}".`)
                        return template
                    } catch (error) {
                        lemonToast.error(errorDetail(error, 'Could not reject the dashboard.'))
                        return values.template
                    }
                },
            },
        ],
        previewDashboardId: [
            null as number | null,
            {
                openPreview: async () => {
                    try {
                        const { dashboard_id } = await metricsDashboardTemplatesPreviewCreate(
                            String(values.currentTeamId),
                            values.templateId as string
                        )
                        return dashboard_id
                    } catch (error) {
                        throw new Error(errorDetail(error, 'Could not build the preview dashboard.'))
                    }
                },
            },
        ],
    })),
    reducers({
        statusFilter: [
            'pending_review' as ReviewStatusFilter,
            {
                setStatusFilter: (_, { statusFilter }) => statusFilter,
            },
        ],
        templateId: [
            null as string | null,
            {
                setTemplateId: (_, { templateId }) => templateId,
            },
        ],
        template: {
            setTemplateId: () => null,
        },
        previewDashboardId: {
            setTemplateId: () => null,
        },
        previewError: [
            null as string | null,
            {
                setPreviewError: (_, { previewError }) => previewError,
                setTemplateId: () => null,
                openPreview: () => null,
            },
        ],
    }),
    selectors({
        reviewable: [
            (s) => [s.template],
            (template: MetricsDashboardTemplateApi | null): boolean =>
                !!template && ['pending_review', 'rejected'].includes(template.status) && template.source !== 'curated',
        ],
        breadcrumbs: [
            (s) => [s.template, s.templateId],
            (template: MetricsDashboardTemplateApi | null, templateId: string | null): Breadcrumb[] => [
                { key: 'Metrics', name: 'Metrics', path: urls.metrics() },
                { key: 'MetricsDashboardReview', name: 'Dashboard review', path: urls.metricsDashboardReview() },
                ...(templateId
                    ? [
                          {
                              key: ['MetricsDashboardTemplate', templateId] as [string, string],
                              name: template?.name ?? 'Dashboard',
                          },
                      ]
                    : []),
            ],
        ],
    }),
    listeners(({ actions, values }) => ({
        setStatusFilter: () => {
            actions.loadTemplates()
        },
        setTemplateId: ({ templateId }) => {
            if (templateId) {
                actions.loadTemplate()
            } else {
                actions.loadTemplates()
            }
        },
        loadTemplateSuccess: ({ template }) => {
            if (template && template.status !== 'generating') {
                actions.openPreview()
            }
        },
        openPreviewFailure: ({ error }) => {
            actions.setPreviewError(error)
        },
        approveTemplateSuccess: () => {
            actions.loadTemplates()
        },
        rejectTemplateSuccess: () => {
            actions.loadTemplates()
        },
        analyzeProject: async () => {
            try {
                await metricsDashboardTemplatesAnalyzeCreate(String(values.currentTeamId))
                lemonToast.success('Analysis started. New dashboards appear here in a few minutes.')
            } catch (error) {
                lemonToast.error(errorDetail(error, 'Could not start the analysis.'))
            }
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.metricsDashboardReview(':templateId')]: ({ templateId }) => {
            if (templateId && templateId !== values.templateId) {
                actions.setTemplateId(templateId)
            }
        },
        [urls.metricsDashboardReview()]: () => {
            if (values.templateId !== null) {
                actions.setTemplateId(null)
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (!values.templateId) {
            actions.loadTemplates()
        }
    }),
])
