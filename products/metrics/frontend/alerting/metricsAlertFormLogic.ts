import { MakeLogicType, afterMount, connect, kea, key, path, props } from 'kea'
import { DeepPartialMap, ValidationErrorType, forms } from 'kea-forms'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { ApiError } from 'lib/api'
import { teamLogic } from 'scenes/teamLogic'

import { platformAlertsCreate, platformAlertsPartialUpdate } from 'products/alerts_platform/frontend/generated/api'
import {
    MetricsPlatformAlertConfigurationCreateApiSourceKind,
    PatchedMetricsPlatformAlertConfigurationEditApiSourceKind,
    PlatformAlertConfigurationApi,
} from 'products/alerts_platform/frontend/generated/api.schemas'

import { metricsAlertingLogic } from './metricsAlertingLogic'
import { MetricsAlertFormType, buildFormDefaults, toWritePayload, validateForm } from './metricsAlertUtils'

export interface MetricsAlertFormLogicProps {
    alert: PlatformAlertConfigurationApi | null
    onSubmitSuccess?: () => void
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsAlertFormLogicValues {
    currentTeamId: number | null // teamLogic
    alertForm: MetricsAlertFormType
    alertFormChanged: boolean
    alertFormErrors: DeepPartialMap<MetricsAlertFormType, ValidationErrorType>
    alertFormHasErrors: boolean
    alertFormValidationErrors: DeepPartialMap<MetricsAlertFormType, ValidationErrorType>
    isAlertFormSubmitting: boolean
    showAlertFormErrors: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsAlertFormLogicActions {
    loadAlerts: (_?: any) => any // metricsAlertingLogic
    resetAlertForm: (values?: MetricsAlertFormType) => {
        values?: MetricsAlertFormType
    }
    setAlertFormValue: (
        key: keyof MetricsAlertFormType,
        value: any
    ) => {
        name: keyof MetricsAlertFormType
        value: any
    }
    setAlertFormValues: (values: Partial<MetricsAlertFormType>) => {
        values: Partial<MetricsAlertFormType>
    }
    submitAlertForm: () => {
        value: true
    }
    touchAlertFormField: (key: keyof MetricsAlertFormType) => {
        key: keyof MetricsAlertFormType
    }
}

export type metricsAlertFormLogicType = MakeLogicType<
    metricsAlertFormLogicValues,
    metricsAlertFormLogicActions,
    MetricsAlertFormLogicProps
>

function saveErrorMessage(error: unknown): string {
    const detail = (error as ApiError | undefined)?.detail
    return detail ? `Could not save the alert: ${detail}` : 'Could not save the alert. Try again.'
}

export const metricsAlertFormLogic = kea<metricsAlertFormLogicType>([
    path((key) => ['products', 'metrics', 'frontend', 'alerting', 'metricsAlertFormLogic', key]),
    props({} as MetricsAlertFormLogicProps),
    key(({ alert }) => alert?.id ?? 'new'),

    connect({
        values: [teamLogic, ['currentTeamId']],
        actions: [metricsAlertingLogic, ['loadAlerts']],
    }),

    afterMount(({ actions, props }) => {
        // kea keeps a keyed logic's form between mounts, so a reopened modal starts from the saved alert.
        actions.resetAlertForm(buildFormDefaults(props.alert))
    }),

    forms(({ props, actions, values }) => ({
        alertForm: {
            defaults: buildFormDefaults(props.alert),
            // A labels error describes the whole list, so it does not fit the per-item shape kea-forms infers.
            errors: (form) => validateForm(form) as DeepPartialMap<MetricsAlertFormType, ValidationErrorType>,
            submit: async (form) => {
                const projectId = String(values.currentTeamId)
                const payload = toWritePayload(form)
                try {
                    if (props.alert) {
                        await platformAlertsPartialUpdate(projectId, props.alert.id, {
                            source_kind: PatchedMetricsPlatformAlertConfigurationEditApiSourceKind.Metrics,
                            ...payload,
                        })
                        posthog.capture('metrics alert updated', { condition_kind: form.conditionKind })
                        lemonToast.success('Alert updated')
                    } else {
                        await platformAlertsCreate(projectId, {
                            source_kind: MetricsPlatformAlertConfigurationCreateApiSourceKind.Metrics,
                            ...payload,
                        })
                        posthog.capture('metrics alert created', {
                            condition_kind: form.conditionKind,
                            grouped: form.groupByLabels.length > 0,
                        })
                        lemonToast.success('Alert created')
                    }
                } catch (error) {
                    lemonToast.error(saveErrorMessage(error))
                    throw error
                }
                actions.loadAlerts()
                props.onSubmitSuccess?.()
                return form
            },
        },
    })),
])
