import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'

import {
    platformAlertsDestroy,
    platformAlertsList,
    platformAlertsPartialUpdate,
} from 'products/alerts_platform/frontend/generated/api'
import {
    PatchedMetricsPlatformAlertConfigurationEditApiSourceKind,
    PlatformAlertConfigurationApi,
    PlatformAlertConfigurationSourceKindEnumApi,
} from 'products/alerts_platform/frontend/generated/api.schemas'

const ALERT_POLL_INTERVAL_MS = 30_000

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsAlertingLogicValues {
    currentTeamId: number | null // teamLogic
    alerts: PlatformAlertConfigurationApi[]
    alertsLoadFailed: boolean
    alertsLoaded: boolean
    alertsLoading: boolean
    togglingAlertIds: Set<string>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsAlertingLogicActions {
    alertUpdated: (alert: PlatformAlertConfigurationApi) => {
        alert: PlatformAlertConfigurationApi
    }
    deleteAlert: (alert: PlatformAlertConfigurationApi) => {
        alert: PlatformAlertConfigurationApi
    }
    loadAlerts: (_?: any) => any
    loadAlertsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAlertsSuccess: (
        alerts: PlatformAlertConfigurationApi[],
        payload?: any
    ) => {
        alerts: PlatformAlertConfigurationApi[]
        payload?: any
    }
    setTogglingAlertId: (
        id: string,
        toggling: boolean
    ) => {
        id: string
        toggling: boolean
    }
    toggleAlertEnabled: (alert: PlatformAlertConfigurationApi) => {
        alert: PlatformAlertConfigurationApi
    }
}

export type metricsAlertingLogicType = MakeLogicType<metricsAlertingLogicValues, metricsAlertingLogicActions>

export const metricsAlertingLogic = kea<metricsAlertingLogicType>([
    path(['products', 'metrics', 'frontend', 'alerting', 'metricsAlertingLogic']),

    connect({
        values: [teamLogic, ['currentTeamId']],
    }),

    actions({
        deleteAlert: (alert: PlatformAlertConfigurationApi) => ({ alert }),
        toggleAlertEnabled: (alert: PlatformAlertConfigurationApi) => ({ alert }),
        setTogglingAlertId: (id: string, toggling: boolean) => ({ id, toggling }),
        alertUpdated: (alert: PlatformAlertConfigurationApi) => ({ alert }),
    }),

    loaders(({ values }) => ({
        alerts: [
            [] as PlatformAlertConfigurationApi[],
            {
                loadAlerts: async (_ = null, breakpoint) => {
                    // The platform caps metrics alerts per team well under one page, so one request holds them all.
                    const response = await platformAlertsList(String(values.currentTeamId), {
                        source_kind: PlatformAlertConfigurationSourceKindEnumApi.Metrics,
                        limit: 100,
                    })
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),

    reducers({
        alerts: {
            alertUpdated: (state, { alert }) => state.map((row) => (row.id === alert.id ? alert : row)),
        },
        // An empty list only means the team has no alerts once a load has succeeded.
        alertsLoaded: [false, { loadAlertsSuccess: () => true }],
        // A poll that fails after a good load keeps the rows on screen rather than replacing them with an error.
        alertsLoadFailed: [false, { loadAlertsSuccess: () => false, loadAlertsFailure: () => true }],
        togglingAlertIds: [
            new Set<string>(),
            {
                setTogglingAlertId: (state, { id, toggling }) =>
                    toggling ? new Set([...state, id]) : new Set([...state].filter((x) => x !== id)),
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        deleteAlert: async ({ alert }) => {
            try {
                await platformAlertsDestroy(String(values.currentTeamId), alert.id)
                lemonToast.success('Alert deleted')
                actions.loadAlerts()
            } catch {
                lemonToast.error('Could not delete the alert. Try again.')
            }
        },
        toggleAlertEnabled: async ({ alert }) => {
            const enabled = !alert.enabled
            actions.setTogglingAlertId(alert.id, true)
            try {
                const updated = await platformAlertsPartialUpdate(String(values.currentTeamId), alert.id, {
                    source_kind: PatchedMetricsPlatformAlertConfigurationEditApiSourceKind.Metrics,
                    enabled,
                })
                // The switch shows the saved value before its loading state clears, so a second click reverses it.
                actions.alertUpdated(updated)
                posthog.capture('metrics alert enabled toggled', { enabled })
                actions.loadAlerts()
            } catch {
                lemonToast.error('Could not update the alert. Try again.')
            } finally {
                actions.setTogglingAlertId(alert.id, false)
            }
        },
    })),

    afterMount(({ actions, cache }) => {
        actions.loadAlerts()
        cache.disposables.add(() => {
            const intervalId = window.setInterval(() => actions.loadAlerts(), ALERT_POLL_INTERVAL_MS)
            return () => clearInterval(intervalId)
        }, 'pollAlerts')
    }),
])
