// A metric name can appear under more than one OTel type, so option identity
// must include both. \0 can't occur in ingest strings, so the key is collision-free.
export const metricOptionKey = (name: string, metricType: string): string => `${name}\0${metricType}`

// Series the metrics query derives from a team's spans, so the panels work for any team that sends traces.
const SPAN_REQUESTS = 'posthog.derived.spans.requests'
const SPAN_ERRORS = 'posthog.derived.spans.errors'
const SPAN_DURATION = 'posthog.derived.spans.duration'
const SPAN_METRICS_PREFIX = 'posthog.derived.spans.'
const BY_SERVICE = [{ key: 'service.name' }]
const LATENCY_QUANTILES = [0.5, 0.95, 0.99]
// These panels read raw spans. Over 24 hours a team with heavy tracing exceeds the query's read budget.
const SPAN_PANEL_DATE_RANGE = { date_from: '-6h' }

type StarterInsight = { name: string; query: MetricsQuery }

// Request rate, error rate and latency per service: the standard view of a service's health.
export function servicePanels(serviceFilter: Pick<MetricsQueryClause, 'filters'>): StarterInsight[] {
    const requestRate = (name: string, metricName: string): MetricsQueryClause => ({
        name,
        metricName,
        metricType: 'sum',
        aggregation: 'sum',
        rangeFunction: 'rate',
        groupBy: BY_SERVICE,
        ...serviceFilter,
    })
    return [
        {
            name: 'Request rate by service',
            query: {
                kind: NodeKind.MetricsQuery,
                clauses: [requestRate('a', SPAN_REQUESTS)],
                dateRange: SPAN_PANEL_DATE_RANGE,
            },
        },
        {
            name: 'Error rate by service',
            query: {
                kind: NodeKind.MetricsQuery,
                clauses: [requestRate('a', SPAN_ERRORS), requestRate('b', SPAN_REQUESTS)],
                formula: 'a / b',
                dateRange: SPAN_PANEL_DATE_RANGE,
            },
        },
        ...LATENCY_QUANTILES.map((quantile) => ({
            name: `Latency p${Math.round(quantile * 100)} by service`,
            query: {
                kind: NodeKind.MetricsQuery as const,
                dateRange: SPAN_PANEL_DATE_RANGE,
                clauses: [
                    {
                        name: 'a',
                        metricName: SPAN_DURATION,
                        metricType: 'histogram' as const,
                        aggregation: 'quantile' as const,
                        quantile,
                        groupBy: BY_SERVICE,
                        ...serviceFilter,
                    },
                ],
            },
        })),
    ]
}

