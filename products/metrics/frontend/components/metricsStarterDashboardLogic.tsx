// One dashboard, one insight per picked metric, each charted as one line per
// series and scoped to the picked service — the onboarding doc's starter set,
// productized. A team that sends traces also gets request rate, error rate and
// latency panels per service.
export const metricsStarterDashboardLogic = kea<metricsStarterDashboardLogicType>([
    path(['products', 'metrics', 'frontend', 'components', 'metricsStarterDashboardLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        openModal: true,
        closeModal: true,
        setDashboardName: (dashboardName: string) => ({ dashboardName }),
        setServiceName: (serviceName: string) => ({ serviceName }),
        setIncludeServicePanels: (includeServicePanels: boolean) => ({ includeServicePanels }),
        // selectedMetrics holds metricOptionKey() composites, not bare names.
        setSelectedMetrics: (selectedMetrics: string[]) => ({ selectedMetrics }),
        createDashboard: true,
        createDashboardSuccess: (createdDashboard: DashboardType, warning?: string) => ({ createdDashboard, warning }),
        createDashboardFailure: (message: string) => ({ message }),
    }),
    reducers({
        isModalOpen: [false, { openModal: () => true, closeModal: () => false }],
        // The whole form resets on close so a reopen can't silently mint a near-duplicate.
        dashboardName: [
            '' as string,
            { setDashboardName: (_, { dashboardName }) => dashboardName, closeModal: () => '' },
        ],
        // '' = all services: the insights get no service filter.
        serviceName: ['' as string, { setServiceName: (_, { serviceName }) => serviceName, closeModal: () => '' }],
        includeServicePanels: [
            true as boolean,
            {
                setIncludeServicePanels: (_, { includeServicePanels }) => includeServicePanels,
                closeModal: () => true,
            },
        ],
        selectedMetrics: [
            [] as string[],
            { setSelectedMetrics: (_, { selectedMetrics }) => selectedMetrics, closeModal: () => [] },
        ],
        // Drives the create button's loading/disabled state so a double click can't
        // fire twice; the listener's cache flag is the authoritative in-flight guard.
        creating: [
            false,
            {
                createDashboard: () => true,
                createDashboardSuccess: () => false,
                createDashboardFailure: () => false,
            },
        ],
    }),
    loaders(({ values }) => ({
        services: [
            [] as string[],
            {
                loadServices: async (_, breakpoint) => {
                    await breakpoint(100)
                    const response = await metricsAttributeValuesRetrieve(String(values.currentTeamId), {
                        key: 'service.name',
                    })
                    breakpoint()
                    return response.results.map((value) => value.name)
                },
            },
        ],
        servicePanelsAvailable: [
            false,
            {
                loadServicePanelsAvailable: async (_, breakpoint) => {
                    // The query runner rejects span-derived series without tracing access,
                    // so these panels would only show errors.
                    if (!userHasAccess(AccessControlResourceType.Tracing, AccessControlLevel.Viewer)) {
                        return false
                    }
                    await breakpoint(100)
                    // A separate search, because the derived names come after the ingested
                    // ones and a team with many metrics would not see them in the picker list.
                    const response = await metricsNamesRetrieve(String(values.currentTeamId), {
                        value: SPAN_METRICS_PREFIX,
                    })
                    breakpoint()
                    const names = new Set(response.results.map((option) => option.name))
                    return [SPAN_REQUESTS, SPAN_ERRORS, SPAN_DURATION].every((name) => names.has(name))
                },
            },
        ],
        metricOptions: [
            [] as _MetricPickerNameApi[],
            {
                loadMetricOptions: async (_, breakpoint) => {
                    await breakpoint(100)
                    const response = await metricsNamesRetrieve(String(values.currentTeamId), {})
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),
    listeners(({ actions, values, cache }) => ({
        openModal: () => {
            actions.loadServices({})
            actions.loadMetricOptions({})
            actions.loadServicePanelsAvailable({})
        },
        createDashboard: async () => {
            // kea-loaders doesn't dedupe concurrent runs, so the create is a plain
            // listener with an explicit in-flight guard.
            if (cache.creatingDashboard) {
                return
            }
            cache.creatingDashboard = true
            // Snapshot the form before the first await: a modal dismissed or edited
            // mid-create must not change (or empty) what gets created.
            const name = values.dashboardName.trim()
            const selectedMetrics = [...values.selectedMetrics]
            const serviceName = values.serviceName
            const optionByKey: Record<string, _MetricPickerNameApi> = Object.fromEntries(
                values.metricOptions.map((option) => [metricOptionKey(option.name, option.metric_type), option])
            )
            // Resolve keys to options up front so a name shared by two OTel types
            // keeps the type the user actually picked.
            const pickedMetrics: _MetricPickerNameApi[] = selectedMetrics.map(
                (key) => optionByKey[key] ?? { name: key, metric_type: '' }
            )
            const serviceFilter = serviceName
                ? { filters: [{ key: 'service.name', op: 'eq' as const, value: serviceName }] }
                : {}
            const extraInsights =
                values.includeServicePanels && values.servicePanelsAvailable ? servicePanels(serviceFilter) : []
            const expectedInsights = selectedMetrics.length + extraInsights.length
            let dashboard: DashboardType | null = null
            let created = 0
            try {
                if (!name || !expectedInsights) {
                    actions.createDashboardFailure('Pick a dashboard name and at least one metric')
                    return
                }
                // The core dashboards create endpoint has no generated client yet
                // (only its sharing sub-resources are in the codegen surface), so this
                // stays a manual call until the Dashboard viewset is tagged.
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. Use dashboardsCreate() from 'products/dashboards/frontend/generated/api' instead.
                dashboard = await api.create<DashboardType>(`api/projects/${values.currentTeamId}/dashboards/`, {
                    name,
                })
                for (const { name: metricName, metric_type: rawType } of pickedMetrics) {
                    // The names endpoint reports raw ingest strings; only enum members
                    // may reach the API — mirrors the viewer's metricsQueryNode.
                    const metricType = toKnownMetricType(rawType)
                    const clause: MetricsQueryClause = {
                        name: 'a',
                        metricName,
                        ...(metricType ? { metricType } : {}),
                        ...serviceFilter,
                    }
                    const query: MetricsQuery = { kind: NodeKind.MetricsQuery, clauses: [clause] }
                    await insightsApi.create({ name: metricName, saved: true, query }, [dashboard.id])
                    created++
                }
                for (const insight of extraInsights) {
                    await insightsApi.create({ ...insight, saved: true }, [dashboard.id])
                    created++
                }
                actions.createDashboardSuccess(dashboard)
            } catch (error: any) {
                if (dashboard) {
                    // The dashboard exists with a partial insight set — say so and take
                    // the user there rather than implying nothing happened (a retry
                    // from the modal would mint a duplicate dashboard). The warning
                    // replaces the success toast so only one shows.
                    actions.createDashboardSuccess(
                        dashboard,
                        `Dashboard "${dashboard.name}" created, but only ${created} of ${expectedInsights} insights could be added`
                    )
                } else {
                    actions.createDashboardFailure(error?.detail || error?.message || 'Failed to create the dashboard')
                }
            } finally {
                cache.creatingDashboard = false
            }
        },
        createDashboardSuccess: ({ createdDashboard, warning }) => {
            actions.closeModal()
            if (warning) {
                lemonToast.warning(warning)
            } else {
                lemonToast.success(`Dashboard "${createdDashboard.name}" created`)
            }
            router.actions.push(urls.dashboard(createdDashboard.id))
        },
        createDashboardFailure: ({ message }) => {
            lemonToast.error(message)
        },
    })),
])
