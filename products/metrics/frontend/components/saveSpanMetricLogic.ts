import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'

import { logsMetricRulesCreate } from 'products/logs/frontend/generated/api'

import { metricsLogsSourceLogic } from './metricsLogsSourceLogic'
import type { SpanMetricRuleDraft } from './spanMetricRuleDraft'

// Mirrors METRIC_NAME_PATTERN in products/logs/backend/presentation/views/metric_rules_api.py.
const METRIC_NAME_PATTERN = /^[a-zA-Z][a-zA-Z0-9._-]*$/
// Mirrors RESERVED_METRIC_NAME_PREFIX there: derived series own these names.
const RESERVED_METRIC_NAME_PREFIX = 'posthog.derived.'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface saveSpanMetricLogicValues {
    currentTeamId: number | null // teamLogic
    draft: SpanMetricRuleDraft | null
    metricName: string
    metricNameError: string | null
    openCount: number
    submitting: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface saveSpanMetricLogicActions {
    loadLogsMetricRules: () => any // metricsLogsSourceLogic
    closeSaveSpanMetric: () => {
        value: true
    }
    openSaveSpanMetric: (draft: SpanMetricRuleDraft) => {
        draft: SpanMetricRuleDraft
    }
    setMetricName: (metricName: string) => {
        metricName: string
    }
    submitSpanMetric: () => {
        value: true
    }
    submitSpanMetricDone: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface saveSpanMetricLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        metricNameError: (metricName: string) => string | null
    }
}

export type saveSpanMetricLogicType = MakeLogicType<
    saveSpanMetricLogicValues,
    saveSpanMetricLogicActions,
    Record<string, any>,
    saveSpanMetricLogicMeta
>

export const metricNameError = (metricName: string): string | null => {
    const name = metricName.trim()
    if (!name) {
        return 'Enter a metric name.'
    }
    if (!METRIC_NAME_PATTERN.test(name)) {
        return 'Start with a letter and use only letters, digits, dots, underscores and dashes.'
    }
    if (name.startsWith(RESERVED_METRIC_NAME_PREFIX)) {
        return `Names starting with ${RESERVED_METRIC_NAME_PREFIX} are reserved.`
    }
    return null
}

/** The "Save as metric" modal: turns a derived span query into a span metric rule. */
export const saveSpanMetricLogic = kea<saveSpanMetricLogicType>([
    path(['products', 'metrics', 'frontend', 'components', 'saveSpanMetricLogic']),

    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [metricsLogsSourceLogic, ['loadLogsMetricRules']],
    })),

    actions({
        openSaveSpanMetric: (draft: SpanMetricRuleDraft) => ({ draft }),
        closeSaveSpanMetric: true,
        setMetricName: (metricName: string) => ({ metricName }),
        submitSpanMetric: true,
        submitSpanMetricDone: true,
    }),

    reducers({
        draft: [
            null as SpanMetricRuleDraft | null,
            {
                openSaveSpanMetric: (_, { draft }) => draft,
                closeSaveSpanMetric: () => null,
            },
        ],
        metricName: [
            '',
            {
                openSaveSpanMetric: (_, { draft }) => draft.rule.metric_name,
                setMetricName: (_, { metricName }) => metricName,
            },
        ],
        // Bumped on every open, so a save from an earlier opening can't close or reset a later one.
        openCount: [
            0,
            {
                openSaveSpanMetric: (count) => count + 1,
            },
        ],
        submitting: [
            false,
            {
                submitSpanMetric: () => true,
                submitSpanMetricDone: () => false,
                closeSaveSpanMetric: () => false,
            },
        ],
    }),

    selectors({
        metricNameError: [(s) => [s.metricName], (metricName: string): string | null => metricNameError(metricName)],
    }),

    listeners(({ actions, values }) => ({
        submitSpanMetric: async () => {
            const { draft, metricNameError: error, openCount } = values
            if (!draft || error) {
                actions.submitSpanMetricDone()
                return
            }
            const name = values.metricName.trim()
            try {
                await logsMetricRulesCreate(String(values.currentTeamId), {
                    ...draft.rule,
                    metric_name: name,
                    enabled: true,
                })
                lemonToast.success(`Created ${name}. It counts spans from now on.`)
                actions.loadLogsMetricRules()
                if (values.openCount === openCount && values.draft) {
                    actions.closeSaveSpanMetric()
                }
            } catch (e: any) {
                lemonToast.error(e?.detail ?? e?.message ?? "Couldn't create the metric. Try again.")
                if (values.openCount === openCount) {
                    actions.submitSpanMetricDone()
                }
            }
        },
    })),
])
