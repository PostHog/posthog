import { MakeLogicType, afterMount, connect, kea, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { logsMetricRulesList } from 'products/logs/frontend/generated/api'
import type { LogsMetricRuleApi } from 'products/logs/frontend/generated/api.schemas'

/**
 * Deep link into the Logs product scoped to the rule's own filters. The stored filter_group is
 * already the two-level group shape the logs scene's urlToAction decodes, so it goes out verbatim.
 */
export function logsUrlForMetricRule(rule: LogsMetricRuleApi): string {
    if (!rule.filter_group) {
        return urls.logs()
    }
    return `${urls.logs()}?filterGroup=${encodeURIComponent(JSON.stringify(rule.filter_group))}`
}

