export type metricsLogsSourceLogicType = MakeLogicType<
    metricsLogsSourceLogicValues,
    metricsLogsSourceLogicActions,
    Record<string, any>,
    metricsLogsSourceLogicMeta
>

/**
 * Loads the team's logs metric rules so the viewer can mark metrics that are generated from logs
 * and link back to their source. Rules are matched by metric_name, which is unique per team and
 * immutable, so it is a stable join key.
 */
export const metricsLogsSourceLogic = kea<metricsLogsSourceLogicType>([
    path(['products', 'metrics', 'frontend', 'components', 'metricsLogsSourceLogic']),

    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    loaders(({ values }) => ({
        logsMetricRules: [
            [] as LogsMetricRuleApi[],
            {
                loadLogsMetricRules: async () => {
                    // The endpoint is flag-gated server-side; a team without logs metric rules
                    // must see a viewer without the tag, not an error.
                    try {
                        const response = await logsMetricRulesList(String(values.currentTeamId))
                        return response.results
                    } catch {
                        return []
                    }
                },
            },
        ],
    })),

    selectors({
        ruleByMetricName: [
            (s) => [s.logsMetricRules],
            (rules: LogsMetricRuleApi[]): Record<string, LogsMetricRuleApi> =>
                Object.fromEntries(rules.map((rule) => [rule.metric_name, rule])),
        ],
    }),

    afterMount(({ actions }) => {
        actions.loadLogsMetricRules()
    }),
])
