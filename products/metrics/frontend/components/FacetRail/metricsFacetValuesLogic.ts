/**
 * One facet's values and data point counts for the active metric. A collapsed facet does not fetch,
 * so a metric with many attributes costs one query per facet the user opens.
 */
export const metricsFacetValuesLogic = kea<metricsFacetValuesLogicType>([
    props({} as MetricsFacetValuesLogicProps),
    key((props) => props.facet.key),
    path((key) => ['products', 'metrics', 'frontend', 'components', 'FacetRail', 'metricsFacetValuesLogic', key]),
    connect(() => ({
        values: [
            metricsViewerLogic,
            ['metricName', 'dateFrom', 'dateTo', 'timezone', 'currentTeamId'],
            metricsFacetRailLogic,
            ['collapsedFacetKeys'],
        ],
        actions: [metricsViewerLogic, ['liveRefreshTick']],
    })),
    actions({
        setFacetSearch: (search: string) => ({ search }),
        retryFacetValues: true,
    }),
    reducers({
        facetSearch: ['', { setFacetSearch: (_, { search }) => search }],
        fetchFailed: [
            false,
            {
                loadFacetValues: () => false,
                loadFacetValuesSuccess: () => false,
                loadFacetValuesFailure: () => true,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        facetValues: [
            [] as FacetOption[],
            {
                loadFacetValues: async (_, breakpoint) => {
                    if (!canViewMetrics() || !values.currentTeamId) {
                        return []
                    }
                    await breakpoint(300)
                    // Collapsed while this was still debouncing: nobody can see the list, so skip the request.
                    if (values.collapsed) {
                        return values.facetValues
                    }
                    const dateFrom = resolveDate(values.dateFrom, values.timezone)
                    const dateTo = resolveDate(values.dateTo, values.timezone)
                    const response = await metricsAttributeValuesRetrieve(String(values.currentTeamId), {
                        key: props.facet.attributeKey,
                        ...(values.metricName.trim() ? { metricName: values.metricName.trim() } : {}),
                        ...(values.facetSearch.trim() ? { value: values.facetSearch.trim() } : {}),
                        ...(dateFrom ? { dateFrom } : {}),
                        ...(dateTo ? { dateTo } : {}),
                        limit: FACET_VALUES_LIMIT,
                    })
                    breakpoint()
                    return response.results.map((row) => ({ value: row.name, label: row.name, count: row.count }))
                },
            },
        ],
    })),
    selectors({
        collapsed: [
            (s, p) => [s.collapsedFacetKeys, p.facet],
            (collapsedFacetKeys: string[], facet: MetricFacetConfig): boolean => collapsedFacetKeys.includes(facet.key),
        ],
        // Null while collapsed, so opening a facet fetches and closing one does not.
        fetchScope: [
            (s) => [s.collapsed, s.metricName, s.dateFrom, s.dateTo, s.currentTeamId, s.facetSearch],
            (
                collapsed: boolean,
                metricName: string,
                dateFrom: string | null,
                dateTo: string | null,
                teamId: number | null,
                facetSearch: string
            ): string | null =>
                collapsed ? null : JSON.stringify([metricName.trim(), dateFrom, dateTo, teamId, facetSearch.trim()]),
        ],
    }),
    subscriptions(({ actions }) => ({
        fetchScope: (scope: string | null) => {
            if (scope !== null) {
                actions.loadFacetValues({})
            }
        },
    })),
    listeners(({ actions, values }) => ({
        retryFacetValues: () => actions.loadFacetValues({}),
        // A load still in flight is left to finish, because a restart would discard its result.
        liveRefreshTick: () => {
            if (!values.collapsed && !values.facetValuesLoading) {
                actions.loadFacetValues({})
            }
        },
    })),
])
