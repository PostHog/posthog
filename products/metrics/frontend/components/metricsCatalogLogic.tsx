import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { metricsValuesRetrieve } from '../generated/api'
import type { _MetricNameApi } from '../generated/api.schemas'
import { canViewMetrics } from '../metricsAccess'
import { metricsSceneLogic } from '../metricsSceneLogic'
import { metricNamePickerLogic } from './metricNamePickerLogic'
import { metricsViewerLogic, toKnownMetricType } from './metricsViewerLogic'

/** One catalog card: a metric name plus what makes it scannable before opening it. */
export type MetricCatalogItem = _MetricNameApi

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsCatalogLogicValues {
    pickerServices: string[]; // metricNamePickerLogic
    currentTeamId: number | null; // teamLogic
    catalogItems: MetricCatalogItem[];
    catalogItemsLoading: boolean;
    search: string;
    visibleItems: MetricCatalogItem[];
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsCatalogLogicActions {
    setServices: (services: string[]) => {
        services: string[];
    }; // metricNamePickerLogic
    setActiveTab: (activeTab: import("../metricsSceneLogic").MetricsSceneActiveTab) => {
        activeTab: import("../metricsSceneLogic").MetricsSceneActiveTab;
    }; // metricsSceneLogic
    setMetricName: (metricName: string) => {
        metricName: string;
    }; // metricsViewerLogic
    setSelectedMetricType: (metricType: null | import("../generated/api.schemas").OtelMetricTypeEnumApi) => {
        metricType: null | import("../generated/api.schemas").OtelMetricTypeEnumApi;
    }; // metricsViewerLogic
    loadCatalog: (_: any) => any;
    loadCatalogFailure: (error: string, errorObject?: any) => {
        error: string;
        errorObject?: any;
    };
    loadCatalogSuccess: (catalogItems: _MetricNameApi[], payload?: any) => {
        catalogItems: _MetricNameApi[];
        payload?: any;
    };
    openMetric: (item: MetricCatalogItem) => {
        item: _MetricNameApi;
    };
    setSearch: (search: string) => {
        search: string;
    };
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsCatalogLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        visibleItems: (catalogItems: _MetricNameApi[], search: string) => MetricCatalogItem[];
    };
}

export type metricsCatalogLogicType = MakeLogicType<metricsCatalogLogicValues, metricsCatalogLogicActions, Record<string, any>, metricsCatalogLogicMeta>;

export const metricsCatalogLogic = kea<metricsCatalogLogicType>([
    path(['products', 'metrics', 'frontend', 'components', 'metricsCatalogLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], metricNamePickerLogic, ['services as pickerServices']],
        actions: [
            metricsViewerLogic,
            ['setMetricName', 'setSelectedMetricType'],
            metricsSceneLogic,
            ['setActiveTab'],
            metricNamePickerLogic,
            ['setServices'],
        ],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        // A card click hands the metric to the viewer and switches to it.
        openMetric: (item: MetricCatalogItem) => ({ item }),
    }),
    reducers({
        search: ['' as string, { setSearch: (_, { search }) => search }],
    }),
    loaders(({ values }) => ({
        catalogItems: [
            [] as MetricCatalogItem[],
            {
                loadCatalog: async (_, breakpoint) => {
                    if (!canViewMetrics()) {
                        return []
                    }
                    await breakpoint(50)
                    // The catalog is scoped to whatever services the picker is
                    // currently pinned to (a service entered from the overview, or
                    // the viewer's own scope), so the cards match what the user
                    // clicked into. The endpoint returns the sparkline and unit.
                    const response = await metricsValuesRetrieve(String(values.currentTeamId), {
                        limit: 500,
                        ...(values.pickerServices.length ? { service: values.pickerServices.join(',') } : {}),
                    })
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),
    selectors({
        visibleItems: [
            (s) => [s.catalogItems, s.search],
            (catalogItems: MetricCatalogItem[], search: string): MetricCatalogItem[] => {
                const needle = search.trim().toLowerCase()
                if (!needle) {
                    return catalogItems
                }
                return catalogItems.filter((item) => item.name.toLowerCase().includes(needle))
            },
        ],
    }),
    listeners(({ actions }) => ({
        // Re-scope: entering a service from the overview or a viewer filter change
        // re-reads the cards for that scope.
        setServices: () => {
            actions.loadCatalog()
        },
        openMetric: ({ item }) => {
            // Set the type first so it latches: a metric name reused across OTel
            // types (a counter and a gauge) charts only the picked type, and the
            // viewer's recommended-aggregation backfill keys off the latched type.
            actions.setSelectedMetricType(toKnownMetricType(item.metric_type))
            actions.setMetricName(item.name)
            actions.setActiveTab('viewer')
        },
    })),
    afterMount(({ actions }) => {
        if (canViewMetrics()) {
            actions.loadCatalog()
        }
    }),
])
