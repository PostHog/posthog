export const metricsCatalogLogic = kea<metricsCatalogLogicType>([
    path(['products', 'metrics', 'frontend', 'components', 'metricsCatalogLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], metricNamePickerLogic, ['services as pickerServices']],
        actions: [
            metricsViewerLogic,
            ['setMetricName', 'setSelectedMetricType'],
            metricsSceneLogic,
            ['setActiveTab'],
            metricNamePickerLogic,
            ['setServices'],
        ],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        loadSparkline: (item: MetricCatalogItem) => ({ item }),
        setSparklineLoading: (name: string) => ({ name }),
        loadSparklineSuccess: (name: string, item: _MetricNameApi) => ({ name, item }),
        loadSparklineFailure: (name: string) => ({ name }),
        retrySparkline: (item: MetricCatalogItem) => ({ item }),
        // A card click hands the metric to the viewer and switches to it.
        openMetric: (item: MetricCatalogItem) => ({ item }),
    }),
    reducers({
        search: ['' as string, { setSearch: (_, { search }) => search }],
        // Details depend on the service scope. Drop the old scope as soon as a
        // replacement name list starts loading, so a late card can never show a
        // sparkline from the service the person just left.
        catalogItemDetails: [
            {} as Record<string, _MetricNameApi>,
            {
                loadCatalog: () => ({}),
                loadSparklineSuccess: (state, { name, item }) => ({ ...state, [name]: item }),
            },
        ],
        catalogItemDetailsFailed: [
            {} as Record<string, boolean>,
            {
                loadCatalog: () => ({}),
                loadSparklineFailure: (state, { name }) => ({ ...state, [name]: true }),
                retrySparkline: (state, { item }) => ({ ...state, [item.name]: false }),
            },
        ],
        catalogItemDetailsLoading: [
            {} as Record<string, boolean>,
            {
                loadCatalog: () => ({}),
                setSparklineLoading: (state, { name }) => ({ ...state, [name]: true }),
                loadSparklineSuccess: (state, { name }) => ({ ...state, [name]: false }),
                loadSparklineFailure: (state, { name }) => ({ ...state, [name]: false }),
            },
        ],
    }),
    loaders(({ values }) => ({
        catalogItems: [
            [] as MetricCatalogItem[],
            {
                loadCatalog: async (): Promise<MetricCatalogItem[]> => {
                    if (!canViewMetrics()) {
                        return []
                    }
                    // The catalog is scoped to whatever services the picker is
                    // currently pinned to (a service entered from the overview, or
                    // the viewer's own scope), so the cards match what the user
                    // clicked into. It returns only names; visible cards load their
                    // own sparkline later instead of one query sampling every metric.
                    const response = await metricsNamesRetrieve(String(values.currentTeamId), {
                        limit: 500,
                        ...(values.pickerServices.length ? { service: values.pickerServices.join(',') } : {}),
                    })
                    return response.results
                },
            },
        ],
    })),
    selectors({
        visibleItems: [
            (s) => [s.catalogItems, s.search],
            (catalogItems: MetricCatalogItem[], search: string): MetricCatalogItem[] => {
                const needle = search.trim().toLowerCase()
                if (!needle) {
                    return catalogItems
                }
                return catalogItems.filter((item) => item.name.toLowerCase().includes(needle))
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        // Re-scope: entering a service from the overview or a viewer filter change
        // re-reads the cards for that scope.
        setServices: () => {
            actions.loadCatalog()
        },
        // No kea breakpoint here: its counter is per action type, not per card, so
        // the next card scrolling into view would abort every request still in
        // flight and leave those cards on an error they never actually hit.
        loadSparkline: async ({ item }) => {
            // An IntersectionObserver can notify more than once while a card is
            // near the viewport. Keep one request per name and retry only after a
            // failed request or after the catalog scope changes.
            if (values.catalogItemDetails[item.name] || values.catalogItemDetailsLoading[item.name]) {
                return
            }
            const teamId = values.currentTeamId
            const services = values.pickerServices
            // The service scope can change while the query runs. The name list was
            // reset for that new scope, so neither a late result nor a late
            // rejection may land on a card that now belongs to another scope.
            const stillInScope = (): boolean =>
                teamId === values.currentTeamId && services.join('\u0000') === values.pickerServices.join('\u0000')
            actions.setSparklineLoading(item.name)
            try {
                const response = await metricsValuesRetrieve(String(teamId), {
                    value: item.name,
                    limit: 1,
                    ...(services.length ? { service: services.join(',') } : {}),
                })
                if (!stillInScope()) {
                    return
                }
                // A name can disappear between the first request and this lazy
                // lookup. Treat that the same as a metric with no recent points,
                // which stops an observer retry loop for a stale card.
                actions.loadSparklineSuccess(item.name, response.results[0] ?? { ...item, sparkline: [] })
            } catch {
                if (!stillInScope()) {
                    return
                }
                actions.loadSparklineFailure(item.name)
            }
        },
        retrySparkline: ({ item }) => {
            actions.loadSparkline(item)
        },
        openMetric: ({ item }) => {
            // Set the type first so it latches: a metric name reused across OTel
            // types (a counter and a gauge) charts only the picked type, and the
            // viewer's recommended-aggregation backfill keys off the latched type.
            actions.setSelectedMetricType(toKnownMetricType(item.metric_type))
            actions.setMetricName(item.name)
            actions.setActiveTab('viewer')
        },
    })),
    afterMount(({ actions }) => {
        if (canViewMetrics()) {
            actions.loadCatalog()
        }
    }),
])
