import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic, FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { teamLogic } from 'scenes/teamLogic'

import { metricsNamesRetrieve } from 'products/metrics/frontend/generated/api'
import type { _MetricPickerNameApi } from 'products/metrics/frontend/generated/api.schemas'
import { canViewMetrics } from 'products/metrics/frontend/metricsAccess'

export type MetricNameItem = _MetricPickerNameApi

// The API maximum. Most teams have fewer names, so one load holds the whole list
// and search filters it locally without a request.
export const METRIC_NAMES_LIMIT = 1000
const SEARCH_LIMIT = 100

/** Same rank as the backend search: exact, then prefix, then suffix, then server order. */
export function filterMetricNames(items: MetricNameItem[], search: string): MetricNameItem[] {
    const needle = search.trim().toLowerCase()
    if (!needle) {
        return items
    }
    const rank = (name: string): number =>
        name === needle ? 0 : name.startsWith(needle) ? 1 : name.endsWith(needle) ? 2 : 3
    return items
        .map((item) => ({ item, name: item.name.toLowerCase() }))
        .filter(({ name }) => name.includes(needle))
        .sort((a, b) => rank(a.name) - rank(b.name))
        .map(({ item }) => item)
}

function mergeMetricNames(items: MetricNameItem[], incoming: MetricNameItem[]): MetricNameItem[] {
    const known = new Set(items.map((item) => item.name))
    const added = incoming.filter((item) => !known.has(item.name))
    return added.length ? [...items, ...added] : items
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricNamePickerLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentTeamId: number | null // teamLogic
    filteredItems: MetricNameItem[]
    items: MetricNameItem[]
    itemsComplete: boolean
    itemsLoading: boolean
    search: string
    services: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricNamePickerLogicActions {
    loadItems: () => any
    loadItemsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadItemsSuccess: (
        items: _MetricPickerNameApi[],
        payload?: any
    ) => {
        items: _MetricPickerNameApi[]
        payload?: any
    }
    searchItems: () => any
    searchItemsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    searchItemsSuccess: (
        items: _MetricPickerNameApi[],
        payload?: any
    ) => {
        items: _MetricPickerNameApi[]
        payload?: any
    }
    primeItems: () => {
        value: true
    }
    setSearch: (search: string) => {
        search: string
    }
    setServices: (services: string[]) => {
        services: string[]
    }
}

export type metricNamePickerLogicType = MakeLogicType<metricNamePickerLogicValues, metricNamePickerLogicActions>

export const metricNamePickerLogic = kea<metricNamePickerLogicType>([
    path(['products', 'metrics', 'frontend', 'components', 'metricNamePickerLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        // Loads the list once per mount. The scene gate calls it again after the feature preview is on,
        // because the scene logic mounts this logic before the gate renders.
        primeItems: true,
        setSearch: (search: string) => ({ search }),
        // Pushed in by the viewer rather than read from it: the viewer already
        // reads this logic's `items`, so a connection the other way would cycle.
        setServices: (services: string[]) => ({ services }),
    }),
    reducers({
        search: ['' as string, { setSearch: (_, { search }) => search }],
        services: [[] as string[], { setServices: (_, { services }) => services }],
        // True when the full load fit under the limit: then local filtering sees
        // every name in the scope, and a search needs no request.
        itemsComplete: [
            false,
            {
                setServices: () => false,
                loadItemsSuccess: (_, { items }) => items.length < METRIC_NAMES_LIMIT,
            },
        ],
    }),
    loaders(({ values }) => {
        const fetchNames = (search: string, limit: number): Promise<{ results: MetricNameItem[] }> =>
            metricsNamesRetrieve(String(values.currentTeamId), {
                value: search,
                limit,
                // Joined here rather than passed as an array: the generated
                // client stringifies params, and an empty array would send
                // `service=`, which the API reads as the unnamed-sender scope.
                ...(values.services.length ? { service: values.services.join(',') } : {}),
            })
        return {
            items: [
                [] as MetricNameItem[],
                {
                    // The full list for the current scope. Replaces what was loaded before.
                    loadItems: async (_, breakpoint) => {
                        if (!canViewMetrics()) {
                            return []
                        }
                        const response = await fetchNames('', METRIC_NAMES_LIMIT)
                        breakpoint()
                        return response.results
                    },
                    // Background search for names past the loaded list. Adds to the list,
                    // so the dropdown keeps the local matches while it runs.
                    searchItems: async (_, breakpoint) => {
                        const search = values.search.trim()
                        if (!canViewMetrics() || !search) {
                            return values.items
                        }
                        // Keystrokes only — matches the 300ms cadence used in the viewer logic.
                        await breakpoint(300)
                        const services = values.services
                        const response = await fetchNames(search, SEARCH_LIMIT)
                        breakpoint()
                        // A scope change while this ran reloads the list; old-scope names must not join it.
                        if (services !== values.services) {
                            return values.items
                        }
                        return mergeMetricNames(values.items, response.results)
                    },
                },
            ],
        }
    }),
    selectors({
        filteredItems: [(s) => [s.items, s.search], filterMetricNames],
    }),
    listeners(({ actions, values, cache }) => ({
        primeItems: () => {
            if (cache.primed || !canViewMetrics()) {
                return
            }
            cache.primed = true
            actions.loadItems()
        },
        setSearch: () => {
            if (!values.itemsComplete && values.search.trim()) {
                actions.searchItems()
            }
        },
        // Not debounced: the scope changes on a click, not a keystroke.
        setServices: () => {
            actions.loadItems()
        },
        // The full load replaces any names a search added, so search again if the list is partial.
        loadItemsSuccess: () => {
            if (!values.itemsComplete && values.search.trim()) {
                actions.searchItems()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        // Prime the list so the dropdown isn't empty on first open. Mirrors
        // serviceFilterLogic's afterMount in logs. Without the flag the API rejects the request.
        if (values.featureFlags[FEATURE_FLAGS.METRICS]) {
            actions.primeItems()
        }
    }),
])
