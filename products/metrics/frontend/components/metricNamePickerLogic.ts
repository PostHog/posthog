export const metricNamePickerLogic = kea<metricNamePickerLogicType>([
    path(['products', 'metrics', 'frontend', 'components', 'metricNamePickerLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        // Loads the list once per mount. The scene gate calls it again after the feature preview is on,
        // because the scene logic mounts this logic before the gate renders.
        primeItems: true,
        openPicker: true,
        dropSearchedItems: (names: string[]) => ({ names }),
        setSearch: (search: string) => ({ search }),
        // Pushed in by the viewer rather than read from it: the viewer already
        // reads this logic's `items`, so a connection the other way would cycle.
        setServices: (services: string[]) => ({ services }),
    }),
    reducers({
        search: ['' as string, { setSearch: (_, { search }) => search }],
        services: [[] as string[], { setServices: (_, { services }) => services }],
        // True when the full load fit under the limit: then local filtering sees
        // every name in the scope, and a search with local matches needs no request.
        itemsComplete: [
            false,
            {
                setServices: () => false,
                loadItemsSuccess: (_, { fullItems }) => fullItems.length < METRIC_NAMES_LIMIT,
            },
        ],
    }),
    loaders(({ values, cache }) => {
        const fetchNames = async (
            search: string,
            limit: number,
            breakpoint: BreakPointFunction
        ): Promise<{ results: MetricNameItem[] }> => {
            try {
                return await metricsNamesRetrieve(String(values.currentTeamId), {
                    value: search,
                    limit,
                    // Joined here rather than passed as an array: the generated
                    // client stringifies params, and an empty array would send
                    // `service=`, which the API reads as the unnamed-sender scope.
                    ...(values.services.length ? { service: values.services.join(',') } : {}),
                })
            } finally {
                // Also on a failure: a request a newer call replaced must not end that call's loading state.
                breakpoint()
            }
        }
        return {
            // The full list for the current scope.
            fullItems: [
                [] as MetricNameItem[],
                {
                    loadItems: async (_: void, breakpoint) => {
                        if (!canViewMetrics()) {
                            return []
                        }
                        const response = await fetchNames('', METRIC_NAMES_LIMIT, breakpoint)
                        return response.results
                    },
                },
            ],
            // Names a server search found past the full list. Kept apart from the full list, so a
            // search never ends the full load's loading state or replaces its names.
            searchedItems: [
                [] as MetricNameItem[],
                {
                    // Runs on every search change, so a newer call cancels a pending one even when it sends nothing.
                    searchItems: async (_: void, breakpoint) => {
                        const search = values.search.trim()
                        if (!canViewMetrics() || !search || (values.itemsComplete && values.filteredItems.length > 0)) {
                            return values.searchedItems
                        }
                        // Keystrokes only — matches the 300ms cadence used in the viewer logic.
                        await breakpoint(300)
                        const services = values.services
                        const response = await fetchNames(search, SEARCH_LIMIT, breakpoint)
                        // A scope change while this ran cleared the list; old-scope names must not join it.
                        if (services !== values.services) {
                            return values.searchedItems
                        }
                        // Per name: a later search can find old-scope names again in the new scope.
                        cache.searchScopes ??= new Map<string, string[]>()
                        for (const item of response.results) {
                            cache.searchScopes.set(item.name, services)
                        }
                        // The newest reply replaces older entries, so a name keeps its type in the current scope.
                        const replied = new Set(response.results.map((item) => item.name))
                        return mergeMetricNames(
                            values.searchedItems.filter((item) => !replied.has(item.name)),
                            response.results
                        )
                    },
                },
            ],
        }
    }),
    reducers({
        searchedItems: {
            dropSearchedItems: (state, { names }) => {
                const dropped = new Set(names)
                return state.filter((item) => !dropped.has(item.name))
            },
        },
        // The old scope's names stay in `items` until the new list arrives, so the viewer can still
        // read the type of a name picked as the scope changes. The dropdown hides them meanwhile.
        scopeLoading: [
            false,
            { setServices: () => true, loadItemsSuccess: () => false, loadItemsFailure: () => false },
        ],
    }),
    selectors({
        items: [
            (s) => [s.fullItems, s.searchedItems],
            (fullItems: MetricNameItem[], searchedItems: MetricNameItem[]): MetricNameItem[] =>
                mergeMetricNames(fullItems, searchedItems),
        ],
        filteredItems: [
            (s) => [s.items, s.search, s.scopeLoading],
            (items: MetricNameItem[], search: string, scopeLoading: boolean): MetricNameItem[] =>
                scopeLoading ? [] : filterMetricNames(items, search),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        primeItems: () => {
            if (cache.primed || !canViewMetrics()) {
                return
            }
            cache.primed = true
            actions.loadItems()
        },
        openPicker: () => {
            const stale = !cache.loadedAt || Date.now() - cache.loadedAt > STALE_AFTER_MS
            if (cache.primed && !values.fullItemsLoading && (stale || values.fullItems.length === 0)) {
                actions.loadItems()
            }
        },
        setSearch: () => {
            actions.searchItems()
        },
        // Not debounced: the scope changes on a click, not a keystroke.
        setServices: () => {
            actions.loadItems()
        },
        loadItemsSuccess: () => {
            cache.loadedAt = Date.now()
            const stale = values.searchedItems
                .map((item) => item.name)
                .filter((name) => cache.searchScopes?.get(name) !== values.services)
            if (stale.length) {
                actions.dropSearchedItems(stale)
            }
            if (values.search.trim()) {
                actions.searchItems()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        // Prime the list so the dropdown isn't empty on first open. Mirrors
        // serviceFilterLogic's afterMount in logs. Without the flag the API rejects the request.
        if (values.featureFlags[FEATURE_FLAGS.METRICS]) {
            actions.primeItems()
        }
    }),
])
