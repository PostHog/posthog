function newVariable(variables: MetricsDashboardVariable[]): MetricsDashboardVariable {
    return { name: newVariableName(variables), source: 'custom', customValues: [] } as MetricsDashboardVariable
}

function withSourceSettings(variable: MetricsDashboardVariable, previousSource: string): MetricsDashboardVariable {
    if (variable.source === previousSource || variable.source === 'promql' || variable.source === 'sql') {
        return variable
    }
    // A list and a text input have no query, so a regex left over from a query would only filter All on SQL tiles.
    if (variable.source === 'custom') {
        return { ...variable, regex: null }
    }
    // A text input has one value and no All, so a saved All would match everything with no way to clear it.
    const value = variable.current?.all ? undefined : variable.current?.values[0]
    return {
        ...variable,
        regex: null,
        multi: null,
        includeAll: null,
        allValue: null,
        current: value ? { values: [value] } : null,
    }
}

// The limits of the variable options API.
const MAX_NAME_LENGTH = 128
const MAX_QUERY_LENGTH = 10000
const MAX_CUSTOM_VALUES = 1000
// The forms that the options endpoint accepts for a PromQL query.
const PROMQL_OPTIONS_QUERY = /^\s*(label_values|label_names|metrics|query_result)\s*\(.*\)\s*$/s
// A change to one of these fields changes the values, so the preview loads again.
const PREVIEW_FIELDS = new Set(['source', 'query', 'regex', 'customValues'])

function newVariableName(variables: MetricsDashboardVariable[]): string {
    const names = new Set(variables.map((variable) => variable.name))
    let index = variables.length + 1
    while (names.has(`var${index}`)) {
        index++
    }
    return `var${index}`
}

function usesRegex(variable: MetricsDashboardVariable): boolean {
    return variable.source === 'promql' || variable.source === 'sql'
}

export function variableErrors(variables: MetricsDashboardVariable[]): Record<string, MetricVariableError> {
    // A null prototype, so a variable named `__proto__` gets its own entry.
    const errors: Record<string, MetricVariableError> = Object.create(null)
    const seen = new Set<string>()
    for (const variable of variables) {
        if (variable.name.length > MAX_NAME_LENGTH) {
            errors[variable.name] = { field: 'name', message: `Use at most ${MAX_NAME_LENGTH} characters.` }
        } else if (variable.name.startsWith('__')) {
            errors[variable.name] = {
                field: 'name',
                message: 'Names that start with two underscores are kept for built-in variables, such as $__interval.',
            }
        } else if (!VARIABLE_NAME.test(variable.name)) {
            errors[variable.name] = {
                field: 'name',
                message: 'Use letters, digits and underscores. Do not start with a digit.',
            }
        } else if (seen.has(variable.name)) {
            errors[variable.name] = { field: 'name', message: 'Another variable has this name.' }
        } else if ((variable.source === 'promql' || variable.source === 'sql') && !variable.query?.trim()) {
            errors[variable.name] = { field: 'query', message: 'Write a query that gives the values.' }
        } else if (variable.source === 'promql' && !PROMQL_OPTIONS_QUERY.test(variable.query ?? '')) {
            errors[variable.name] = {
                field: 'query',
                message: 'Use label_values(), label_names(), metrics() or query_result().',
            }
        } else if ((variable.query?.length ?? 0) > MAX_QUERY_LENGTH) {
            errors[variable.name] = { field: 'query', message: `Use at most ${MAX_QUERY_LENGTH} characters.` }
        } else if (
            (variable.source === 'promql' || variable.source === 'sql') &&
            (variable.regex?.length ?? 0) > MAX_VALUE_LENGTH
        ) {
            errors[variable.name] = { field: 'regex', message: `Use at most ${MAX_VALUE_LENGTH} characters.` }
        } else if ((variable.allValue?.length ?? 0) > MAX_VALUE_LENGTH) {
            errors[variable.name] = { field: 'allValue', message: `Use at most ${MAX_VALUE_LENGTH} characters.` }
        } else if (variable.source === 'custom' && !variable.customValues?.length) {
            errors[variable.name] = { field: 'values', message: 'Add at least one value.' }
        } else if ((variable.customValues?.length ?? 0) > MAX_CUSTOM_VALUES) {
            errors[variable.name] = { field: 'values', message: `Use at most ${MAX_CUSTOM_VALUES} values.` }
        } else if (variable.customValues?.some((value) => value.length > MAX_VALUE_LENGTH)) {
            errors[variable.name] = {
                field: 'values',
                message: `A value can have at most ${MAX_VALUE_LENGTH} characters.`,
            }
        }
        seen.add(variable.name)
    }
    const names = new Set(variables.map((variable) => variable.name))
    for (const variable of variables) {
        if (ownValue(errors, variable.name) || (variable.source !== 'promql' && variable.source !== 'sql')) {
            continue
        }
        // A label_replace replacement can use `$name` for a regex group, which the server leaves as it is.
        const referenced =
            variable.source === 'sql'
                ? sqlReferencedNames(variable.query)
                : promqlReferencedNames(variable.query, { replacements: false })
        const missing = referenced.find((name) => !names.has(name) && !name.startsWith('__') && !/^\d+$/.test(name))
        if (missing) {
            errors[variable.name] = { field: 'query', message: `$${missing} is not a variable on this dashboard.` }
        }
    }
    for (const name of orderVariables(variables).cycle) {
        if (ownValue(errors, name)) {
            continue
        }
        errors[name] = {
            field: 'query',
            message: 'The query refers to its own variable, or the variable queries refer to each other in a loop.',
        }
    }
    return errors
}

export const metricVariableEditorLogic = kea<metricVariableEditorLogicType>([
    path((key) => ['products', 'metrics', 'frontend', 'components', 'metricVariableEditorLogic', key]),
    props({} as MetricVariableEditorLogicProps),
    key((props) => props.dashboardId),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        addVariable: true,
        schedulePreview: true,
        setPreviewError: (error: string | null) => ({ error }),
        setRegexError: (regex: string, error: string | null) => ({ regex, error }),
        clearRegexErrors: true,
        setApplying: (applying: boolean) => ({ applying }),
        apply: (onSave: (variables: MetricsDashboardVariable[]) => void) => ({ onSave }),
        removeVariable: (index: number) => ({ index }),
        moveVariable: (index: number, offset: -1 | 1) => ({ index, offset }),
        updateVariable: (index: number, patch: Partial<MetricsDashboardVariable>) => ({ index, patch }),
        selectVariable: (index: number) => ({ index }),
    }),
    afterMount(({ actions }) => {
        actions.loadPreview()
    }),
    reducers(({ props }) => ({
        draft: [
            props.addVariableOnOpen ? [...props.variables, newVariable(props.variables)] : props.variables,
            {
                addVariable: (state) => [...state, newVariable(state)],
                removeVariable: (state, { index }) => state.filter((_, other) => other !== index),
                moveVariable: (state, { index, offset }) => {
                    const target = index + offset
                    if (target < 0 || target >= state.length) {
                        return state
                    }
                    const next = [...state]
                    ;[next[index], next[target]] = [next[target], next[index]]
                    return next
                },
                updateVariable: (state, { index, patch }) =>
                    state.map((variable, other) =>
                        other === index ? withSourceSettings({ ...variable, ...patch }, variable.source) : variable
                    ),
            },
        ],
        selectedIndex: [
            props.addVariableOnOpen ? props.variables.length : 0,
            {
                selectVariable: (_, { index }) => index,
                removeVariable: (state, { index }) => (state >= index ? Math.max(state - 1, 0) : state),
                moveVariable: (state, { index, offset }) => (state === index ? state + offset : state),
            },
        ],
        preview: [
            null as string[] | null,
            {
                selectVariable: () => null,
                addVariable: () => null,
                removeVariable: () => null,
            },
        ],
        showAllErrors: [false, { apply: () => true }],
        // The server checks each regex, so its verdicts are kept by pattern.
        regexErrors: [
            {} as Record<string, string>,
            {
                setRegexError: (state, { regex, error }) => {
                    const { [regex]: _, ...rest } = state
                    return error ? { ...rest, [regex]: error } : rest
                },
                clearRegexErrors: () => ({}),
            },
        ],
        applying: [false, { setApplying: (_, { applying }) => applying }],
        touchedIndexes: [
            [] as number[],
            {
                updateVariable: (state, { index }) => (state.includes(index) ? state : [...state, index]),
                removeVariable: (state, { index }) =>
                    state.filter((other) => other !== index).map((other) => (other > index ? other - 1 : other)),
                moveVariable: (state, { index, offset }) =>
                    state.map((other) => (other === index ? index + offset : other === index + offset ? index : other)),
            },
        ],
        previewError: [
            null as string | null,
            {
                loadPreview: () => null,
                setPreviewError: (_, { error }) => error,
                loadPreviewFailure: (_, { error }) => error,
                selectVariable: () => null,
                removeVariable: () => null,
            },
        ],
    })),
    selectors({
        selectedVariable: [
            (s) => [s.draft, s.selectedIndex],
            (draft: MetricsDashboardVariable[], selectedIndex: number): MetricsDashboardVariable | null =>
                draft[selectedIndex] ?? null,
        ],
        errors: [
            (s) => [s.draft, s.regexErrors],
            (
                draft: MetricsDashboardVariable[],
                regexErrors: Record<string, string>
            ): Record<string, MetricVariableError> => {
                const errors = variableErrors(draft)
                for (const variable of draft) {
                    const regexError = variable.regex ? ownValue(regexErrors, variable.regex) : undefined
                    if (regexError && !ownValue(errors, variable.name) && usesRegex(variable)) {
                        errors[variable.name] = { field: 'regex', message: regexError }
                    }
                }
                return errors
            },
        ],
        shownErrors: [
            (s) => [s.errors, s.draft, s.touchedIndexes, s.showAllErrors],
            (
                errors: Record<string, MetricVariableError>,
                draft: MetricsDashboardVariable[],
                touchedIndexes: number[],
                showAllErrors: boolean
            ): Record<string, MetricVariableError> =>
                showAllErrors
                    ? errors
                    : Object.fromEntries(
                          touchedIndexes
                              .map((index: number) => draft[index]?.name)
                              .filter((name: string | undefined): name is string => !!name && !!ownValue(errors, name))
                              .map((name) => [name, errors[name]])
                      ),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        addVariable: () => {
            actions.selectVariable(values.draft.length - 1)
        },
        selectVariable: () => {
            actions.loadPreview()
        },
        removeVariable: () => {
            actions.loadPreview()
        },
        apply: async ({ onSave }, breakpoint) => {
            // A failed check can be a timeout or a rate limit, so each Apply checks the patterns again.
            actions.clearRegexErrors()
            const checked = values.draft
            const firstError = (): number =>
                values.draft.findIndex((variable) => ownValue(values.errors, variable.name))
            if (firstError() === -1) {
                // The server checks a regex without running a query, so a pattern it rejects is never saved.
                const unchecked = new Set(
                    values.draft
                        .filter((variable) => usesRegex(variable) && variable.regex?.trim())
                        .map((variable) => variable.regex!)
                        .filter((regex) => !(cache.validRegexes as Set<string> | undefined)?.has(regex))
                )
                actions.setApplying(true)
                try {
                    await Promise.all(
                        [...unchecked].map(async (regex) => {
                            try {
                                await metricsVariableOptionsCreate(String(values.currentTeamId), {
                                    source: 'custom',
                                    customValues: [],
                                    regex,
                                })
                                ;(cache.validRegexes ??= new Set<string>()).add(regex)
                            } catch (error) {
                                const detail =
                                    error && typeof error === 'object' && 'detail' in error ? error.detail : null
                                actions.setRegexError(
                                    regex,
                                    typeof detail === 'string' ? detail : 'The regex could not be checked. Try again.'
                                )
                            }
                        })
                    )
                } finally {
                    actions.setApplying(false)
                }
                // Closing the editor or editing it while the check runs cancels the Apply.
                breakpoint()
                if (values.draft !== checked) {
                    return
                }
            }
            const index = firstError()
            if (index === -1) {
                onSave(values.draft)
            } else {
                actions.selectVariable(index)
            }
        },
        updateVariable: ({ patch }) => {
            // A separate action waits, so an edit to another field does not cancel the pending preview.
            if (Object.keys(patch).some((field) => PREVIEW_FIELDS.has(field))) {
                actions.schedulePreview()
            }
        },
        schedulePreview: async (_, breakpoint) => {
            await breakpoint(600)
            actions.loadPreview()
        },
    })),
    loaders(({ actions, values, props, cache }) => ({
        preview: {
            loadPreview: async (_: void, breakpoint): Promise<string[] | null> => {
                // A cancelled fetch leaves its query running on the server, so a preview waits for the one before it.
                // A newer edit made during the wait cancels this preview.
                if (cache.previewRequest) {
                    await cache.previewRequest.catch(() => undefined)
                    breakpoint()
                }
                const variable = values.selectedVariable
                if (
                    !variable ||
                    variable.source === 'textbox' ||
                    variable.source === 'custom' ||
                    !variable.query?.trim() ||
                    // The server would run the query before it rejects what the editor already rejects.
                    ['query', 'regex'].includes(ownValue(values.errors, variable.name)?.field ?? '')
                ) {
                    return null
                }
                // A parent added in this session has no selection yet, so the preview uses its first option.
                const draft = values.draft.map((other) =>
                    other.current
                        ? other
                        : {
                              ...other,
                              current: reconcileSelection(
                                  other,
                                  other.source === 'custom'
                                      ? [...new Set((other.customValues ?? []).filter(Boolean))]
                                      : (ownValue(props.options, other.name) ?? [])
                              ),
                          }
                )
                const request = metricsVariableOptionsCreate(String(values.currentTeamId), {
                    source: variable.source,
                    query: variable.query ?? null,
                    regex: variable.regex ?? null,
                    variables: selectionsForRequest(variable, draft, props.options),
                    dateFrom: props.dateFrom ?? null,
                    dateTo: props.dateTo ?? null,
                })
                cache.previewRequest = request
                let response
                try {
                    response = await request
                } catch (error) {
                    breakpoint()
                    // A rejected query echoes its text, which can hold customer data, so it is shown and not reported.
                    const detail = error && typeof error === 'object' && 'detail' in error ? error.detail : null
                    actions.setPreviewError(typeof detail === 'string' ? detail : 'The values could not be loaded.')
                    return null
                }
                breakpoint()
                return response.results
            },
        },
    })),
])
