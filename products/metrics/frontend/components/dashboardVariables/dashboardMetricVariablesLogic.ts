function errorMessage(error: unknown): string {
    if (error && typeof error === 'object' && 'detail' in error && typeof error.detail === 'string') {
        return error.detail
    }
    return error instanceof Error ? error.message : 'The options could not be loaded.'
}

export const dashboardMetricVariablesLogic = kea<dashboardMetricVariablesLogicType>([
    path((key) => ['products', 'metrics', 'frontend', 'components', 'dashboardMetricVariablesLogic', key]),
    props({} as DashboardMetricVariablesLogicProps),
    key((props) => props.dashboardId),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        loadOptions: (names: string[] | null, reconcile: boolean) => ({ names, reconcile }),
        setOptions: (name: string, options: string[]) => ({ name, options }),
        setError: (name: string, error: string | null) => ({ name, error }),
        setLoading: (name: string, loading: boolean) => ({ name, loading }),
        setReconciledVariables: (variables: MetricsDashboardVariable[]) => ({ variables }),
        retry: (name: string) => ({ name }),
    }),
    reducers({
        options: [
            {} as Record<string, string[]>,
            { setOptions: (state, { name, options }) => ({ ...state, [name]: options }) },
        ],
        errors: [
            {} as Record<string, string>,
            {
                setError: (state, { name, error }) => {
                    const { [name]: _, ...rest } = state
                    return error ? { ...rest, [name]: error } : rest
                },
            },
        ],
        loadingNames: [
            [] as string[],
            {
                setLoading: (state, { name, loading }) =>
                    loading ? [...state.filter((other) => other !== name), name] : state.filter((n) => n !== name),
            },
        ],
        reconciledVariables: [
            null as MetricsDashboardVariable[] | null,
            { setReconciledVariables: (_, { variables }) => variables },
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        loadOptions: async ({ names, reconcile }, breakpoint) => {
            // A newer load cancels this one at its next breakpoint, so its unfinished names move to the newer load.
            const pending: Set<string> | null =
                names === null || cache.pending === null
                    ? null
                    : new Set([...((cache.pending as Set<string> | undefined) ?? []), ...names])
            const shouldReconcile = reconcile || !!cache.pendingReconcile
            cache.pending = pending
            cache.pendingReconcile = shouldReconcile
            let variables = props.variables

            // Each variable loads when its parents finish, and shows its options at once, so a slow
            // query delays only the variables that depend on it.
            const loads = new Map<string, Promise<void>>()
            const load = async (definition: MetricsDashboardVariable): Promise<void> => {
                const { name } = definition
                await Promise.all(variableParents(definition, props.variables).map((parent) => loads.get(parent)))
                breakpoint()
                if ((pending !== null && !pending.has(name)) || definition.source === 'textbox') {
                    return
                }
                // The parents may have changed their selections, which the request must use.
                const variable = variables.find((other) => other.name === name)!
                let options: string[]
                if (variable.source === 'custom') {
                    options = [...new Set((variable.customValues ?? []).filter(Boolean))]
                } else {
                    actions.setLoading(name, true)
                    try {
                        const response = await metricsVariableOptionsCreate(String(values.currentTeamId), {
                            source: variable.source,
                            query: variable.query ?? null,
                            variables: selectionsForRequest(variable, variables, values.options),
                            // The server resolves the dashboard date filter as the tiles do.
                            dateFrom: props.dateFrom ?? null,
                            dateTo: props.dateTo ?? null,
                        })
                        breakpoint()
                        options = applyVariableRegex(response.results, variable.regex)
                    } catch (error) {
                        breakpoint()
                        actions.setLoading(name, false)
                        pending?.delete(name)
                        // Keep the options and the selection: they are unknown now, not empty.
                        actions.setError(name, errorMessage(error))
                        return
                    }
                    actions.setLoading(name, false)
                }
                pending?.delete(name)
                actions.setError(name, null)
                actions.setOptions(name, options)
                const current = reconcileSelection(variable, options)
                if (!objectsEqual(current, variable.current ?? null)) {
                    variables = variables.map((other) => (other.name === name ? { ...other, current } : other))
                }
            }
            for (const name of orderVariables(props.variables).order) {
                loads.set(name, load(props.variables.find((variable) => variable.name === name)!))
            }
            await Promise.allSettled(loads.values())
            breakpoint()
            cache.pending = undefined
            cache.pendingReconcile = false
            // The first load only shows options. A saved selection changes only after the user changes something.
            if (shouldReconcile && variables !== props.variables) {
                actions.setReconciledVariables(variables)
                props.onSelectionsChange(variables)
            }
        },
        retry: ({ name }) => {
            // The variables that depend on a failed variable kept options that its new values can change.
            actions.loadOptions([name, ...dependentsOf(props.variables, [name])], true)
        },
    })),
    propsChanged(({ actions, values, props }, oldProps) => {
        if (props.dateFrom !== oldProps.dateFrom || props.dateTo !== oldProps.dateTo) {
            actions.loadOptions(null, true)
            return
        }
        if (objectsEqual(props.variables, oldProps.variables)) {
            return
        }
        if (values.reconciledVariables && objectsEqual(props.variables, values.reconciledVariables)) {
            return
        }
        const names = variablesToReload(oldProps.variables, props.variables)
        if (names.length) {
            actions.loadOptions(names, true)
        }
    }),
    afterMount(({ actions }) => {
        actions.loadOptions(null, false)
    }),
])
