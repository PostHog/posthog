import {
    MakeLogicType,
    actions,
    afterMount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    propsChanged,
    reducers,
} from 'kea'

import { dateStringToDayJs } from 'lib/utils/dateFilters'
import { objectsEqual } from 'lib/utils/objects'
import { teamLogic } from 'scenes/teamLogic'

import type { MetricsDashboardVariable } from '~/queries/schema/schema-general'

import { metricsVariableOptionsCreate } from 'products/metrics/frontend/generated/api'

import {
    applyVariableRegex,
    orderVariables,
    reconcileSelection,
    selectionsForRequest,
    variablesToReload,
} from './metricVariables'

export interface DashboardMetricVariablesLogicProps {
    dashboardId: number | string
    variables: MetricsDashboardVariable[]
    dateFrom?: string | null
    dateTo?: string | null
    /** Called when loaded options make a selection out of date. */
    onSelectionsChange: (variables: MetricsDashboardVariable[]) => void
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardMetricVariablesLogicValues {
    currentTeamId: number | null // teamLogic
    errors: Record<string, string>
    loadingNames: string[]
    options: Record<string, string[]>
    reconciledVariables: MetricsDashboardVariable[] | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardMetricVariablesLogicActions {
    loadOptions: (
        names: string[] | null,
        reconcile: boolean
    ) => {
        names: string[] | null
        reconcile: boolean
    }
    setError: (
        name: string,
        error: string | null
    ) => {
        name: string
        error: string | null
    }
    setLoading: (
        name: string,
        loading: boolean
    ) => {
        name: string
        loading: boolean
    }
    setOptions: (
        name: string,
        options: string[]
    ) => {
        name: string
        options: string[]
    }
    setReconciledVariables: (variables: MetricsDashboardVariable[]) => {
        variables: MetricsDashboardVariable[]
    }
}

export type dashboardMetricVariablesLogicType = MakeLogicType<
    dashboardMetricVariablesLogicValues,
    dashboardMetricVariablesLogicActions,
    DashboardMetricVariablesLogicProps
>

function errorMessage(error: unknown): string {
    if (error && typeof error === 'object' && 'detail' in error && typeof error.detail === 'string') {
        return error.detail
    }
    return error instanceof Error ? error.message : 'The options could not be loaded.'
}

export const dashboardMetricVariablesLogic = kea<dashboardMetricVariablesLogicType>([
    path((key) => ['products', 'metrics', 'frontend', 'components', 'dashboardMetricVariablesLogic', key]),
    props({} as DashboardMetricVariablesLogicProps),
    key((props) => props.dashboardId),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        loadOptions: (names: string[] | null, reconcile: boolean) => ({ names, reconcile }),
        setOptions: (name: string, options: string[]) => ({ name, options }),
        setError: (name: string, error: string | null) => ({ name, error }),
        setLoading: (name: string, loading: boolean) => ({ name, loading }),
        setReconciledVariables: (variables: MetricsDashboardVariable[]) => ({ variables }),
    }),
    reducers({
        options: [
            {} as Record<string, string[]>,
            { setOptions: (state, { name, options }) => ({ ...state, [name]: options }) },
        ],
        errors: [
            {} as Record<string, string>,
            {
                setError: (state, { name, error }) => {
                    const { [name]: _, ...rest } = state
                    return error ? { ...rest, [name]: error } : rest
                },
            },
        ],
        loadingNames: [
            [] as string[],
            {
                setLoading: (state, { name, loading }) =>
                    loading ? [...state.filter((other) => other !== name), name] : state.filter((n) => n !== name),
            },
        ],
        reconciledVariables: [
            null as MetricsDashboardVariable[] | null,
            { setReconciledVariables: (_, { variables }) => variables },
        ],
    }),
    listeners(({ actions, values, props }) => ({
        loadOptions: async ({ names, reconcile }) => {
            const { order } = orderVariables(props.variables)
            let variables = props.variables
            for (const name of order) {
                if (names && !names.includes(name)) {
                    continue
                }
                const variable = variables.find((other) => other.name === name)
                if (!variable || variable.source === 'textbox') {
                    continue
                }
                let options: string[] = []
                let failed = false
                if (variable.source === 'custom') {
                    options = [...new Set((variable.customValues ?? []).filter(Boolean))]
                    actions.setError(name, null)
                } else {
                    actions.setLoading(name, true)
                    try {
                        const response = await metricsVariableOptionsCreate(String(values.currentTeamId), {
                            source: variable.source,
                            query: variable.query ?? null,
                            variables: selectionsForRequest(variables.filter((other) => other.name !== name)),
                            dateFrom: dateStringToDayJs(props.dateFrom ?? null)?.toISOString() ?? null,
                            dateTo: dateStringToDayJs(props.dateTo ?? null)?.toISOString() ?? null,
                        })
                        options = applyVariableRegex(response.results, variable.regex)
                        actions.setError(name, null)
                    } catch (error) {
                        failed = true
                        actions.setError(name, errorMessage(error))
                    } finally {
                        actions.setLoading(name, false)
                    }
                }
                actions.setOptions(name, options)
                if (failed) {
                    // Keep the selection: the options are unknown, not empty.
                    continue
                }
                const current = reconcileSelection(variable, options)
                if (!objectsEqual(current, variable.current ?? null)) {
                    variables = variables.map((other) => (other.name === name ? { ...other, current } : other))
                }
            }
            // The first load only shows options. A saved selection changes only after the user changes something.
            if (reconcile && variables !== props.variables) {
                actions.setReconciledVariables(variables)
                props.onSelectionsChange(variables)
            }
        },
    })),
    propsChanged(({ actions, values, props }, oldProps) => {
        if (props.dateFrom !== oldProps.dateFrom || props.dateTo !== oldProps.dateTo) {
            actions.loadOptions(null, true)
            return
        }
        if (objectsEqual(props.variables, oldProps.variables)) {
            return
        }
        if (values.reconciledVariables && objectsEqual(props.variables, values.reconciledVariables)) {
            return
        }
        const names = variablesToReload(oldProps.variables, props.variables)
        if (names.length) {
            actions.loadOptions(names, true)
        }
    }),
    afterMount(({ actions }) => {
        actions.loadOptions(null, false)
    }),
])
