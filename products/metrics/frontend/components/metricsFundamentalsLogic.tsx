import { MakeLogicType, actions, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import { dayjs } from 'lib/dayjs'

import { metricsExplainCreate, metricsQueryCreate } from 'products/metrics/frontend/generated/api'
import type { _MetricBucketDecompositionApi } from 'products/metrics/frontend/generated/api.schemas'

import type { MetricAggregation } from './metricsViewerLogic'

// Bucket size the check runs at. Fixed rather than auto-picked, because a
// decomposition is only meaningful next to the interval it was computed for.
export const CHECK_INTERVAL = 'minute_5'

// How far back to look for a bucket with data in it. The most recent bucket is
// usually still filling, so the check walks back to the last complete one.
const LOOKBACK_MINUTES = 60

export interface FundamentalsCheckResult {
    decomposition: _MetricBucketDecompositionApi
    checkedAt: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsFundamentalsLogicValues {
    aggregation: MetricAggregation
    checkResult: FundamentalsCheckResult | null
    checkResultLoading: boolean
    metricName: string
    projectId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsFundamentalsLogicActions {
    runCheck: () => {
        value: true
    }
    runCheckFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    runCheckSuccess: (
        checkResult: {
            checkedAt: string
            decomposition: _MetricBucketDecompositionApi
        } | null,
        payload?: {
            value: true
        }
    ) => {
        checkResult: {
            checkedAt: string
            decomposition: _MetricBucketDecompositionApi
        } | null
        payload?: {
            value: true
        }
    }
    setAggregation: (aggregation: MetricAggregation) => {
        aggregation: MetricAggregation
    }
    setMetricName: (metricName: string) => {
        metricName: string
    }
}

export type metricsFundamentalsLogicType = MakeLogicType<
    metricsFundamentalsLogicValues,
    metricsFundamentalsLogicActions
>

export const metricsFundamentalsLogic = kea<metricsFundamentalsLogicType>([
    path(['products', 'metrics', 'frontend', 'components', 'metricsFundamentalsLogic']),

    actions({
        setMetricName: (metricName: string) => ({ metricName }),
        setAggregation: (aggregation: MetricAggregation) => ({ aggregation }),
        runCheck: true,
    }),

    reducers({
        metricName: ['', { setMetricName: (_, { metricName }) => metricName }],
        aggregation: ['sum' as MetricAggregation, { setAggregation: (_, { aggregation }) => aggregation }],
        // Drop the previous decomposition the moment a new check starts. The
        // loading flag alone leaves a frame where the old answer is still on
        // screen under the new metric name, which reads as the new answer.
        checkResult: [null as FundamentalsCheckResult | null, { runCheck: () => null }],
    }),

    loaders(({ values }) => ({
        checkResult: [
            null as FundamentalsCheckResult | null,
            {
                runCheck: async (_, breakpoint) => {
                    if (!values.metricName) {
                        return null
                    }
                    await breakpoint(300)

                    const dateTo = dayjs().startOf('minute')
                    const dateFrom = dateTo.subtract(LOOKBACK_MINUTES, 'minute')

                    // Ask the chart what it would plot first, so the bucket being
                    // explained is one the product actually drew rather than one
                    // picked blind — an empty bucket explains nothing.
                    const series = await metricsQueryCreate(values.projectId, {
                        query: {
                            metricName: values.metricName,
                            aggregation: values.aggregation,
                            interval: CHECK_INTERVAL,
                            dateFrom: dateFrom.toISOString(),
                            dateTo: dateTo.toISOString(),
                        },
                    })
                    breakpoint()

                    const points = series.results?.[0]?.points ?? []
                    const latest = [...points].reverse().find((point) => point.value !== null)
                    if (!latest) {
                        lemonToast.info(`No data for ${values.metricName} in the last hour`)
                        return null
                    }

                    const response = await metricsExplainCreate(values.projectId, {
                        query: {
                            metricName: values.metricName,
                            aggregation: values.aggregation,
                            bucketStart: latest.time,
                            interval: CHECK_INTERVAL,
                        },
                    })
                    breakpoint()

                    return { decomposition: response.decomposition, checkedAt: dayjs().toISOString() }
                },
            },
        ],
    })),

    selectors({
        projectId: [() => [], () => window.POSTHOG_APP_CONTEXT?.current_project?.id?.toString() ?? ''],
    }),
])
