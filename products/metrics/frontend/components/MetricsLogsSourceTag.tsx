import { useValues } from 'kea'

import { IconLive } from '@posthog/icons'
import { LemonButton, LemonMenu } from '@posthog/lemon-ui'

import { useFeatureFlag } from 'lib/hooks/useFeatureFlag'
import { urls } from 'scenes/urls'

import { logsUrlForMetricRule, metricsLogsSourceLogic } from './metricsLogsSourceLogic'

export interface MetricsLogsSourceTagProps {
    metricName: string
}

/**
 * Marks a metric that is generated from logs by a metric rule, and links back to the source:
 * the logs the rule matches, and the rule itself in settings.
 */
export function MetricsLogsSourceTag({ metricName }: MetricsLogsSourceTagProps): JSX.Element | null {
    const metricRulesEnabled = useFeatureFlag('LOGS_METRIC_RULES')
    if (!metricRulesEnabled || !metricName.trim()) {
        return null
    }
    // Split so the rules fetch only happens (via the logic's mount) when the flag is on.
    return <MetricsLogsSourceTagContent metricName={metricName.trim()} />
}

function MetricsLogsSourceTagContent({ metricName }: MetricsLogsSourceTagProps): JSX.Element | null {
    const { ruleByMetricName } = useValues(metricsLogsSourceLogic)
    const rule = ruleByMetricName[metricName]
    if (!rule) {
        return null
    }
    return (
        <LemonMenu
            items={[
                { label: 'View source logs', to: logsUrlForMetricRule(rule) },
                { label: 'Edit in settings', to: urls.settings('environment-logs', 'logs-metric-rules') },
            ]}
        >
            <LemonButton
                size="xsmall"
                type="secondary"
                icon={<IconLive />}
                tooltip={`Generated by the log-based metric "${rule.name}"`}
                data-attr="metrics-viewer-logs-source"
            >
                From logs
            </LemonButton>
        </LemonMenu>
    )
}
