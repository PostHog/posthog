import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import type { MetricsQuery } from '~/queries/schema/schema-general'
import { MetricsQueryLanguage, NodeKind } from '~/queries/schema/schema-general'

import { metricsValuesRetrieve } from '../generated/api'
import type { _MetricNameApi } from '../generated/api.schemas'
import { canViewMetrics } from '../metricsAccess'
import { metricsSceneLogic } from '../metricsSceneLogic'
import type { MetricsSceneActiveTab } from '../metricsSceneLogic'
import { metricsViewerLogic } from './metricsViewerLogic'

export const SUMMARY_LIMIT = 500

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsSummaryLogicValues {
    language: MetricsQueryLanguage // metricsViewerLogic
    currentTeamId: number | null // teamLogic
    catalogTruncated: boolean
    filteredMetrics: _MetricNameApi[]
    metrics: _MetricNameApi[]
    metricsFailed: boolean
    metricsLoading: boolean
    search: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsSummaryLogicActions {
    setActiveTab: (activeTab: MetricsSceneActiveTab) => {
        activeTab: MetricsSceneActiveTab
    } // metricsSceneLogic
    applyQuery: (query: MetricsQuery) => {
        query: MetricsQuery
    } // metricsViewerLogic
    setMetricName: (metricName: string) => {
        metricName: string
    } // metricsViewerLogic
    loadMetrics: (_: void) => void
    loadMetricsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadMetricsSuccess: (
        metrics: _MetricNameApi[],
        payload?: void
    ) => {
        metrics: _MetricNameApi[]
        payload?: void
    }
    setCatalogTruncated: (catalogTruncated: boolean) => {
        catalogTruncated: boolean
    }
    setSearch: (search: string) => {
        search: string
    }
    viewMetric: (metricName: string) => {
        metricName: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface metricsSummaryLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        filteredMetrics: (metrics: _MetricNameApi[], search: string) => _MetricNameApi[]
    }
}

export type metricsSummaryLogicType = MakeLogicType<
    metricsSummaryLogicValues,
    metricsSummaryLogicActions,
    Record<string, any>,
    metricsSummaryLogicMeta
>

export const metricsSummaryLogic = kea<metricsSummaryLogicType>([
    path(['products', 'metrics', 'frontend', 'components', 'metricsSummaryLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], metricsViewerLogic, ['language']],
        actions: [metricsViewerLogic, ['setMetricName', 'applyQuery'], metricsSceneLogic, ['setActiveTab']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        viewMetric: (metricName: string) => ({ metricName }),
        setCatalogTruncated: (catalogTruncated: boolean) => ({ catalogTruncated }),
    }),
    loaders(({ actions, values }) => ({
        metrics: {
            __default: [] as _MetricNameApi[],
            loadMetrics: async (_: void, breakpoint): Promise<_MetricNameApi[]> => {
                if (!canViewMetrics()) {
                    return values.metrics
                }
                // Only a truncated catalog needs the server to search: otherwise every name is already loaded.
                const value = values.catalogTruncated ? values.search.trim() : ''
                const response = await metricsValuesRetrieve(String(values.currentTeamId), {
                    limit: SUMMARY_LIMIT,
                    sparklines: false,
                    series_stats: true,
                    fold_histograms: true,
                    ...(value ? { value } : {}),
                })
                breakpoint()
                if (!value) {
                    actions.setCatalogTruncated(response.results.length >= SUMMARY_LIMIT)
                }
                return response.results
            },
        },
    })),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        catalogTruncated: [false, { setCatalogTruncated: (_, { catalogTruncated }) => catalogTruncated }],
        metricsFailed: [
            false,
            { loadMetrics: () => false, loadMetricsSuccess: () => false, loadMetricsFailure: () => true },
        ],
    }),
    selectors({
        filteredMetrics: [
            (s) => [s.metrics, s.search],
            (metrics: _MetricNameApi[], search: string): _MetricNameApi[] => {
                const needle = search.trim().toLowerCase()
                return needle ? metrics.filter((metric) => metric.name.toLowerCase().includes(needle)) : metrics
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setSearch: async (_, breakpoint) => {
            if (values.catalogTruncated) {
                await breakpoint(300)
                actions.loadMetrics()
            }
        },
        viewMetric: ({ metricName }) => {
            // setMetricName only edits the builder, so a PromQL or SQL query would otherwise stay on screen.
            if (values.language !== 'builder') {
                actions.applyQuery({ kind: NodeKind.MetricsQuery, clauses: [] })
            }
            actions.setMetricName(metricName)
            actions.setActiveTab('viewer')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadMetrics()
    }),
])
