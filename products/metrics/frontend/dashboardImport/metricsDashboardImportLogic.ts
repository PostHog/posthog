export const metricsDashboardImportLogic = kea<metricsDashboardImportLogicType>([
    path(['products', 'metrics', 'frontend', 'dashboardImport', 'metricsDashboardImportLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        openImportModal: (source: DashboardImportSourceEnumApi) => ({ source }),
        openImport: (dashboardImport: DashboardImportApi) => ({ dashboardImport }),
        closeImportModal: true,
        setGrafanaJson: (grafanaJson: string) => ({ grafanaJson }),
        setDashboardName: (dashboardName: string) => ({ dashboardName }),
        setScreenshotFile: (file: File) => ({ file }),
        setScreenshot: (screenshot: string | null) => ({ screenshot }),
        setScreenshotError: (screenshotError: string) => ({ screenshotError }),
        startImport: true,
        startImportSuccess: (dashboardImport: DashboardImportApi) => ({ dashboardImport }),
        startImportFailure: (error: string, status: number | null) => ({ error, status }),
        loadRecentImports: true,
        setRecentImports: (recentImports: DashboardImportApi[]) => ({ recentImports }),
        openImportedDashboard: (dashboardId: number) => ({ dashboardId }),
        backToInput: true,
        resetImport: true,
    }),
    reducers({
        isModalOpen: [false, { openImportModal: () => true, openImport: () => true, closeImportModal: () => false }],
        source: [
            'grafana' as DashboardImportSourceEnumApi,
            {
                openImportModal: (_, { source }) => source,
                openImport: (_, { dashboardImport }) => dashboardImport.source,
            },
        ],
        grafanaJson: ['', { setGrafanaJson: (_, { grafanaJson }) => grafanaJson, resetImport: () => '' }],
        dashboardName: ['', { setDashboardName: (_, { dashboardName }) => dashboardName, resetImport: () => '' }],
        screenshot: [
            null as string | null,
            { setScreenshot: (_, { screenshot }) => screenshot, resetImport: () => null },
        ],
        screenshotLoading: [
            false,
            { setScreenshotFile: () => true, setScreenshot: () => false, setScreenshotError: () => false },
        ],
        screenshotError: [
            null as string | null,
            {
                setScreenshotError: (_, { screenshotError }) => screenshotError,
                setScreenshotFile: () => null,
                setScreenshot: () => null,
                resetImport: () => null,
            },
        ],
        starting: [
            false,
            { startImport: () => true, startImportSuccess: () => false, startImportFailure: () => false },
        ],
        startError: [
            null as string | null,
            {
                startImportFailure: (_, { error }) => error,
                startImport: () => null,
                setGrafanaJson: () => null,
                setScreenshot: () => null,
                backToInput: () => null,
                resetImport: () => null,
            },
        ],
        // The import that the modal shows. The recent imports refresh it while it runs.
        currentImport: [
            null as DashboardImportApi | null,
            {
                startImportSuccess: (_, { dashboardImport }) => dashboardImport,
                openImport: (_, { dashboardImport }) => dashboardImport,
                setRecentImports: (state, { recentImports }) =>
                    (state?.id && recentImports.find((item) => item.id === state.id)) || state,
                backToInput: () => null,
                resetImport: () => null,
            },
        ],
        recentImports: [
            [] as DashboardImportApi[],
            {
                setRecentImports: (_, { recentImports }) => recentImports,
                // A started import shows in the list at once, before the next refresh.
                startImportSuccess: (state, { dashboardImport }) =>
                    dashboardImport.id
                        ? [dashboardImport, ...state.filter((item) => item.id !== dashboardImport.id)]
                        : state,
            },
        ],
    }),
    selectors({
        step: [
            (s) => [s.currentImport],
            (currentImport: DashboardImportApi | null): DashboardImportStep =>
                !currentImport ? 'input' : currentImport.status === 'running' ? 'progress' : 'summary',
        ],
        runningImports: [
            (s) => [s.recentImports],
            (recentImports: DashboardImportApi[]): DashboardImportApi[] =>
                recentImports.filter((item) => item.status === 'running'),
        ],
        grafanaJsonError: [
            (s) => [s.grafanaJson],
            (grafanaJson: string): string | null => grafanaJsonProblem(grafanaJson),
        ],
        sortedPanels: [
            (s) => [s.currentImport],
            (currentImport: DashboardImportApi | null): DashboardImportPanelApi[] =>
                [...(currentImport?.panels ?? [])].sort((a, b) => OUTCOME_ORDER[a.outcome] - OUTCOME_ORDER[b.outcome]),
        ],
        importDisabledReason: [
            (s) => [s.source, s.grafanaJson, s.grafanaJsonError, s.screenshot, s.screenshotLoading, s.runningImports],
            (
                source: DashboardImportSourceEnumApi,
                grafanaJson: string,
                grafanaJsonError: string | null,
                screenshot: string | null,
                screenshotLoading: boolean,
                runningImports: DashboardImportApi[]
            ): string | null => {
                if (runningImports.length >= MAX_RUNNING_IMPORTS) {
                    return `${MAX_RUNNING_IMPORTS} imports are running. Wait for one of them to finish.`
                }
                if (source === 'grafana') {
                    return !grafanaJson.trim() ? 'Paste the Grafana dashboard JSON' : grafanaJsonError
                }
                if (screenshotLoading) {
                    return 'Reading the screenshot'
                }
                return screenshot ? null : 'Add a screenshot of the dashboard'
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        closeImportModal: () => {
            // An import that runs continues on the server, and the recent imports keep track of it.
            actions.resetImport()
        },
        setScreenshotFile: async ({ file }, breakpoint) => {
            try {
                const screenshot = await readScreenshot(file)
                breakpoint()
                actions.setScreenshot(screenshot)
            } catch (error) {
                const failure = error instanceof Error ? error : new Error('Could not read the screenshot.')
                if (isBreakpoint(failure)) {
                    throw failure
                }
                actions.setScreenshotError(failure.message)
            }
        },
        startImport: async () => {
            // The button shows the loading state. This flag also stops a second request from a quick double click.
            if (cache.startInFlight) {
                return
            }
            cache.startInFlight = true
            const source = values.source
            const name = values.dashboardName.trim()
            const screenshot = values.screenshot ?? ''
            const body: DashboardImportCreateApi = {
                source,
                ...(name ? { name } : {}),
                ...(source === 'grafana'
                    ? { grafana_json: values.grafanaJson }
                    : { image_base64: screenshot.slice(screenshot.indexOf(',') + 1) }),
            }
            try {
                const dashboardImport = await metricsDashboardImportsCreate(String(values.currentTeamId), body)
                actions.startImportSuccess(dashboardImport)
            } catch (error) {
                const apiError = error instanceof ApiError ? error : null
                actions.startImportFailure(
                    apiError?.detail || 'The import did not start. Try again.',
                    apiError?.status ?? null
                )
            } finally {
                cache.startInFlight = false
            }
        },
        startImportSuccess: ({ dashboardImport }) => {
            if (dashboardImport.status === 'running') {
                actions.loadRecentImports()
            }
        },
        loadRecentImports: async () => {
            if (cache.loadInFlight) {
                return
            }
            cache.loadInFlight = true
            try {
                actions.setRecentImports(await metricsDashboardImportsList(String(values.currentTeamId)))
            } catch {
                // The list is a convenience. The next refresh tries again.
            } finally {
                cache.loadInFlight = false
            }
        },
        setRecentImports: ({ recentImports }) => {
            // An import counts as known to run once the list showed it running, so a reload does not repeat old messages.
            const wasRunning: Set<string> = cache.runningIds ?? new Set()
            cache.runningIds = new Set(
                recentImports.filter((item) => item.status === 'running').map((item) => item.id as string)
            )
            for (const dashboardImport of recentImports) {
                const shownInModal = values.isModalOpen && values.currentImport?.id === dashboardImport.id
                if (
                    dashboardImport.status !== 'running' &&
                    wasRunning.has(dashboardImport.id as string) &&
                    !shownInModal
                ) {
                    notifyFinished(dashboardImport, actions)
                }
            }
            if (cache.runningIds.size > 0) {
                cache.disposables.add(() => {
                    const intervalId = setInterval(() => actions.loadRecentImports(), POLL_INTERVAL_MS)
                    return () => clearInterval(intervalId)
                }, POLL_KEY)
            } else {
                cache.disposables.dispose(POLL_KEY)
            }
        },
        openImportedDashboard: ({ dashboardId }) => {
            actions.closeImportModal()
            router.actions.push(urls.dashboard(dashboardId))
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRecentImports()
    }),
])

function notifyFinished(
    dashboardImport: DashboardImportApi,
    actions: {
        openImport: (dashboardImport: DashboardImportApi) => void
        openImportedDashboard: (dashboardId: number) => void
    }
): void {
    const viewSummary = {
        label: 'View summary',
        action: () => actions.openImport(dashboardImport),
        dataAttr: 'metrics-dashboard-import-toast-summary',
    }
    const dashboardId = dashboardImport.dashboard_id
    if (dashboardImport.status === 'completed' && dashboardImport.summary && dashboardId) {
        const { total, imported, approximated } = dashboardImport.summary
        lemonToast.success(
            `The dashboard "${dashboardImport.dashboard_name}" is ready. ${imported + approximated} of ${total} panels were imported.`,
            {
                button: {
                    label: 'Open dashboard',
                    action: () => actions.openImportedDashboard(dashboardId),
                    dataAttr: 'metrics-dashboard-import-toast-open',
                },
                secondaryButton: viewSummary,
            }
        )
    } else {
        lemonToast.error(`The import of "${dashboardImport.dashboard_name}" failed.`, { button: viewSummary })
    }
}
