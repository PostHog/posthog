export const metricsDashboardImportLogic = kea<metricsDashboardImportLogicType>([
    // The path names the localStorage key of `activeImport`. A rename forgets the imports that run.
    path(['products', 'metrics', 'frontend', 'dashboardImport', 'metricsDashboardImportLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        openImportModal: (source: DashboardImportSourceEnumApi) => ({ source }),
        closeImportModal: true,
        setGrafanaJson: (grafanaJson: string) => ({ grafanaJson }),
        setDashboardName: (dashboardName: string) => ({ dashboardName }),
        setScreenshotFile: (file: File) => ({ file }),
        setScreenshot: (screenshot: string | null) => ({ screenshot }),
        setScreenshotError: (screenshotError: string) => ({ screenshotError }),
        startImport: true,
        startImportSuccess: (dashboardImport: DashboardImportApi, teamId: number | null) => ({
            dashboardImport,
            teamId,
        }),
        startImportFailure: (error: string, status: number | null) => ({ error, status }),
        startPolling: true,
        pollImport: true,
        setCurrentImport: (dashboardImport: DashboardImportApi) => ({ dashboardImport }),
        forgetImport: true,
        openImportedDashboard: true,
        backToInput: true,
        resetImport: true,
    }),
    reducers({
        isModalOpen: [false, { openImportModal: () => true, closeImportModal: () => false }],
        source: ['grafana' as DashboardImportSourceEnumApi, { openImportModal: (_, { source }) => source }],
        grafanaJson: ['', { setGrafanaJson: (_, { grafanaJson }) => grafanaJson, resetImport: () => '' }],
        dashboardName: ['', { setDashboardName: (_, { dashboardName }) => dashboardName, resetImport: () => '' }],
        screenshot: [
            null as string | null,
            { setScreenshot: (_, { screenshot }) => screenshot, resetImport: () => null },
        ],
        screenshotLoading: [
            false,
            { setScreenshotFile: () => true, setScreenshot: () => false, setScreenshotError: () => false },
        ],
        screenshotError: [
            null as string | null,
            {
                setScreenshotError: (_, { screenshotError }) => screenshotError,
                setScreenshotFile: () => null,
                setScreenshot: () => null,
                resetImport: () => null,
            },
        ],
        starting: [
            false,
            { startImport: () => true, startImportSuccess: () => false, startImportFailure: () => false },
        ],
        startError: [
            null as string | null,
            {
                startImportFailure: (_, { error }) => error,
                startImport: () => null,
                setGrafanaJson: () => null,
                setScreenshot: () => null,
                backToInput: () => null,
                resetImport: () => null,
            },
        ],
        currentImport: [
            null as DashboardImportApi | null,
            {
                startImportSuccess: (_, { dashboardImport }) => dashboardImport,
                setCurrentImport: (_, { dashboardImport }) => dashboardImport,
                forgetImport: () => null,
                backToInput: () => null,
                resetImport: () => null,
            },
        ],
        // Persisted, so that the scene finds an import that runs after a reload or a visit to another page.
        activeImport: [
            null as ActiveDashboardImport | null,
            { persist: true },
            {
                startImportSuccess: (_, { dashboardImport, teamId }) =>
                    dashboardImport.status === 'running' && dashboardImport.id && teamId
                        ? { id: dashboardImport.id, teamId }
                        : null,
                setCurrentImport: (state, { dashboardImport }) => (dashboardImport.status === 'running' ? state : null),
                forgetImport: () => null,
            },
        ],
    }),
    selectors({
        step: [
            (s) => [s.currentImport, s.activeImport, s.currentTeamId],
            (
                currentImport: DashboardImportApi | null,
                activeImport: ActiveDashboardImport | null,
                currentTeamId: number | null
            ): DashboardImportStep => {
                if (currentImport) {
                    return currentImport.status === 'running' ? 'progress' : 'summary'
                }
                // The status of a running import is not loaded yet. Do not show a form that starts a second import.
                return activeImport && activeImport.teamId === currentTeamId ? 'progress' : 'input'
            },
        ],
        grafanaJsonError: [
            (s) => [s.grafanaJson],
            (grafanaJson: string): string | null => grafanaJsonProblem(grafanaJson),
        ],
        sortedPanels: [
            (s) => [s.currentImport],
            (currentImport: DashboardImportApi | null): DashboardImportPanelApi[] =>
                [...(currentImport?.panels ?? [])].sort((a, b) => OUTCOME_ORDER[a.outcome] - OUTCOME_ORDER[b.outcome]),
        ],
        importDisabledReason: [
            (s) => [s.source, s.grafanaJson, s.grafanaJsonError, s.screenshot, s.screenshotLoading],
            (
                source: DashboardImportSourceEnumApi,
                grafanaJson: string,
                grafanaJsonError: string | null,
                screenshot: string | null,
                screenshotLoading: boolean
            ): string | null => {
                if (source === 'grafana') {
                    return !grafanaJson.trim() ? 'Paste the Grafana dashboard JSON' : grafanaJsonError
                }
                if (screenshotLoading) {
                    return 'Reading the screenshot'
                }
                return screenshot ? null : 'Add a screenshot of the dashboard'
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        closeImportModal: () => {
            // An import that runs continues on the server. Keep its state, so that it can show when it ends.
            if (values.step !== 'progress') {
                actions.resetImport()
            }
        },
        setScreenshotFile: async ({ file }, breakpoint) => {
            try {
                const screenshot = await readScreenshot(file)
                breakpoint()
                actions.setScreenshot(screenshot)
            } catch (error) {
                const failure = error instanceof Error ? error : new Error('Could not read the screenshot.')
                if (isBreakpoint(failure)) {
                    throw failure
                }
                actions.setScreenshotError(failure.message)
            }
        },
        startImport: async () => {
            // The button shows the loading state. This flag also stops a second request from a quick double click.
            if (cache.startInFlight) {
                return
            }
            cache.startInFlight = true
            const source = values.source
            const name = values.dashboardName.trim()
            const screenshot = values.screenshot ?? ''
            const body: DashboardImportCreateApi = {
                source,
                ...(name ? { name } : {}),
                ...(source === 'grafana'
                    ? { grafana_json: values.grafanaJson }
                    : { image_base64: screenshot.slice(screenshot.indexOf(',') + 1) }),
            }
            const teamId = values.currentTeamId
            try {
                const dashboardImport = await metricsDashboardImportsCreate(String(teamId), body)
                actions.startImportSuccess(dashboardImport, teamId)
            } catch (error) {
                const apiError = error instanceof ApiError ? error : null
                actions.startImportFailure(
                    apiError?.detail || 'The import did not start. Try again.',
                    apiError?.status ?? null
                )
            } finally {
                cache.startInFlight = false
            }
        },
        startImportSuccess: ({ dashboardImport }) => {
            if (dashboardImport.status === 'running') {
                actions.startPolling()
            }
        },
        startPolling: () => {
            cache.disposables.add(() => {
                const intervalId = setInterval(() => actions.pollImport(), POLL_INTERVAL_MS)
                return () => clearInterval(intervalId)
            }, POLL_KEY)
        },
        pollImport: async () => {
            const activeImport = values.activeImport
            if (!activeImport || cache.pollInFlight) {
                return
            }
            cache.pollInFlight = true
            try {
                const dashboardImport = await metricsDashboardImportsRetrieve(
                    String(activeImport.teamId),
                    activeImport.id
                )
                actions.setCurrentImport(dashboardImport)
            } catch (error) {
                // A 404 means that the import is gone. Other errors can be temporary, so the next poll tries again.
                if (error instanceof ApiError && error.status === 404) {
                    actions.forgetImport()
                }
            } finally {
                cache.pollInFlight = false
            }
        },
        setCurrentImport: ({ dashboardImport }) => {
            if (dashboardImport.status === 'running') {
                return
            }
            cache.disposables.dispose(POLL_KEY)
            if (values.isModalOpen) {
                return
            }
            const viewSummary = {
                label: 'View summary',
                action: () => actions.openImportModal(dashboardImport.source),
                dataAttr: 'metrics-dashboard-import-toast-summary',
            }
            if (dashboardImport.status === 'completed' && dashboardImport.summary) {
                const { total, imported, approximated } = dashboardImport.summary
                lemonToast.success(
                    `The dashboard "${dashboardImport.dashboard_name}" is ready. ${imported + approximated} of ${total} panels were imported.`,
                    {
                        button: {
                            label: 'Open dashboard',
                            action: () => actions.openImportedDashboard(),
                            dataAttr: 'metrics-dashboard-import-toast-open',
                        },
                        secondaryButton: viewSummary,
                    }
                )
            } else {
                lemonToast.error(`The import of "${dashboardImport.dashboard_name}" failed.`, { button: viewSummary })
            }
        },
        forgetImport: () => {
            cache.disposables.dispose(POLL_KEY)
        },
        openImportedDashboard: () => {
            const dashboardId = values.currentImport?.dashboard_id
            if (dashboardId) {
                actions.closeImportModal()
                router.actions.push(urls.dashboard(dashboardId))
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.activeImport && values.activeImport.teamId === values.currentTeamId) {
            actions.pollImport()
            actions.startPolling()
        }
    }),
])
