// The summary lists the panels that need attention first.
const OUTCOME_ORDER: Record<PanelImportOutcomeEnumApi, number> = { failed: 0, approximated: 1, skipped: 2, imported: 3 }

export type DashboardImportStep = 'input' | 'progress' | 'summary'

export interface ActiveDashboardImport {
    id: string
    teamId: number
}

function grafanaJsonProblem(grafanaJson: string): string | null {
    if (!grafanaJson.trim()) {
        return null
    }
    try {
        const parsed: unknown = JSON.parse(grafanaJson)
        return typeof parsed === 'object' && parsed !== null && !Array.isArray(parsed)
            ? null
            : 'Paste the JSON object of the dashboard.'
    } catch {
        return 'This text is not valid JSON. Copy the JSON model of the dashboard again.'
    }
}

