import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { ApiError } from 'lib/api-error'
import { API_KEY_SCOPE_PRESETS } from 'lib/scopes'
import { apiHostOrigin } from 'lib/utils/apiHost'
import { personalAPIKeysLogic } from 'scenes/settings/user/personalAPIKeysLogic'
import { teamLogic } from 'scenes/teamLogic'

export const GRAFANA_API_KEY_PRESET = 'grafana'

// Grafana runs the same query when it saves a Prometheus data source.
const TEST_QUERY = '1+1'

export type PrometheusConnectionTest = { status: 'success' } | { status: 'error'; message: string }

export type PrometheusConnectSnippet = 'server_url' | 'provisioning'

function connectionErrorMessage(error: unknown): string {
    if (error instanceof ApiError) {
        return error.data?.error || error.detail || `The test query failed with status ${error.status}.`
    }
    return 'The test query failed. Try again later.'
}

