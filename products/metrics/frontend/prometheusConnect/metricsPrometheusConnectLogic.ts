export type metricsPrometheusConnectLogicType = MakeLogicType<
    metricsPrometheusConnectLogicValues,
    metricsPrometheusConnectLogicActions,
    Record<string, any>,
    metricsPrometheusConnectLogicMeta
>

export const metricsPrometheusConnectLogic = kea<metricsPrometheusConnectLogicType>([
    path(['products', 'metrics', 'frontend', 'prometheusConnect', 'metricsPrometheusConnectLogic']),

    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [personalAPIKeysLogic, ['setEditingKeyId', 'setEditingKeyValues']],
    })),

    actions({
        openConnectModal: true,
        closeConnectModal: true,
        snippetCopied: (snippet: PrometheusConnectSnippet) => ({ snippet }),
        createApiKey: true,
    }),

    reducers({
        isConnectModalOpen: [
            false,
            {
                openConnectModal: () => true,
                closeConnectModal: () => false,
            },
        ],
    }),

    loaders(({ values }) => ({
        connectionTest: [
            null as PrometheusConnectionTest | null,
            {
                testConnection: async (): Promise<PrometheusConnectionTest> => {
                    try {
                        // The OpenAPI schema excludes this Prometheus passthrough, so it has no generated client.
                        await api.get(`${values.apiPath}/api/v1/query?query=${encodeURIComponent(TEST_QUERY)}`)
                        return { status: 'success' }
                    } catch (error) {
                        return { status: 'error', message: connectionErrorMessage(error) }
                    }
                },
            },
        ],
    })),

    reducers({
        connectionTest: {
            openConnectModal: () => null,
        },
    }),

    selectors({
        apiPath: [
            (s) => [s.currentTeamId],
            (currentTeamId: number | null): string => `api/projects/${currentTeamId}/metrics/prometheus`,
        ],
        serverUrl: [(s) => [s.apiPath], (apiPath: string): string => `${apiHostOrigin()}/${apiPath}`],
        provisioningSnippet: [
            (s) => [s.serverUrl],
            (serverUrl: string): string =>
                [
                    'apiVersion: 1',
                    'datasources:',
                    '  - name: PostHog',
                    '    type: prometheus',
                    '    access: proxy',
                    `    url: ${serverUrl}`,
                    '    jsonData:',
                    '      httpMethod: POST',
                    '      httpHeaderName1: Authorization',
                    '    secureJsonData:',
                    '      httpHeaderValue1: Bearer $POSTHOG_PERSONAL_API_KEY',
                ].join('\n'),
        ],
    }),

    // pinned: analytics event names and properties, renaming breaks the metrics usage dashboards
    listeners(({ actions }) => ({
        openConnectModal: () => {
            posthog.capture('metrics prometheus connect opened')
        },
        snippetCopied: ({ snippet }) => {
            posthog.capture('metrics prometheus snippet copied', { snippet })
        },
        createApiKey: () => {
            const preset = API_KEY_SCOPE_PRESETS.find((p) => p.value === GRAFANA_API_KEY_PRESET)
            if (preset) {
                actions.setEditingKeyId('new')
                actions.setEditingKeyValues({
                    preset: preset.value,
                    label: preset.label,
                    scopes: preset.scopes,
                    access_type: preset.access_type,
                })
            }
            posthog.capture('metrics prometheus api key create clicked')
        },
        testConnectionSuccess: ({ connectionTest }) => {
            posthog.capture('metrics prometheus connection tested', { success: connectionTest?.status === 'success' })
        },
    })),
])
