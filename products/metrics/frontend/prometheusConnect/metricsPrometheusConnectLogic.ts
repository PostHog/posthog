export interface metricsPrometheusConnectLogicValues {
    currentTeamId: number | null // teamLogic
    apiPath: string
    connectionTest: PrometheusConnectionTest | null
    connectionTestLoading: boolean
    isConnectModalOpen: boolean
    provisioningSnippet: string
    serverUrl: string
}

