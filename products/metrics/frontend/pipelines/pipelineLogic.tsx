import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { projectLogic } from 'scenes/projectLogic'
import { urls } from 'scenes/urls'

import {
    metricsPipelinesCreate,
    metricsPipelinesEvaluateCreate,
    metricsPipelinesPartialUpdate,
    metricsPipelinesRetrieve,
} from '../generated/api'
import { MetricsPipelineApi, PipelineConfigApi, PipelineEvaluationApi } from './types'

export interface PipelineLogicProps {
    /** Pipeline UUID, or 'new' for the creation flow */
    id: string
}

export const NEW_PIPELINE_ID = 'new'
export const AUTO_REFRESH_INTERVAL_MS = 30_000

export const EMPTY_CONFIG: PipelineConfigApi = { nodes: [], edges: [], variables: [] }

export interface PipelineDraft {
    name: string
    description: string
    config: PipelineConfigApi
}

