export type pipelineLogicType = MakeLogicType<
    pipelineLogicValues,
    pipelineLogicActions,
    PipelineLogicProps,
    pipelineLogicMeta
>

export const pipelineLogic = kea<pipelineLogicType>([
    path(['products', 'metrics', 'frontend', 'pipelines', 'pipelineLogic']),
    props({} as PipelineLogicProps),
    key((props: PipelineLogicProps) => props.id),
    connect({ values: [projectLogic, ['currentProjectId']] }),
    actions({
        selectNode: (nodeId: string | null) => ({ nodeId }),
        selectEdge: (edgeKey: string | null) => ({ edgeKey }),
        setVariableValue: (variableKey: string, value: string | null) => ({ variableKey, value }),
        setAutoRefresh: (enabled: boolean) => ({ enabled }),
        startEditing: true,
        cancelEditing: true,
        setDraft: (draft: PipelineDraft) => ({ draft }),
        savePipeline: true,
        // Flips `editing` off only after a persisted update, so the reducer and
        // the save listener share one signal.
        savePipelineSuccess: true,
        refreshTick: true,
    }),
    loaders(({ props, values }) => ({
        pipeline: [
            null as MetricsPipelineApi | null,
            {
                loadPipeline: async () => {
                    if (props.id === NEW_PIPELINE_ID) {
                        return null
                    }
                    return await metricsPipelinesRetrieve(String(values.currentProjectId), props.id)
                },
            },
        ],
        evaluation: [
            null as PipelineEvaluationApi | null,
            {
                evaluate: async (_, breakpoint) => {
                    if (props.id === NEW_PIPELINE_ID) {
                        return null
                    }
                    await breakpoint(100)
                    const response = await metricsPipelinesEvaluateCreate(String(values.currentProjectId), props.id, {
                        variables: values.variableValues,
                    })
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers({
        selectedNodeId: [
            null as string | null,
            {
                selectNode: (_, { nodeId }) => nodeId,
                selectEdge: () => null,
            },
        ],
        selectedEdgeKey: [
            null as string | null,
            {
                selectEdge: (_, { edgeKey }) => edgeKey,
                selectNode: () => null,
            },
        ],
        variableValues: [
            {} as Record<string, string>,
            {
                setVariableValue: (state, { variableKey, value }) => {
                    const next = { ...state }
                    if (value === null) {
                        delete next[variableKey]
                    } else {
                        next[variableKey] = value
                    }
                    return next
                },
            },
        ],
        autoRefreshEnabled: [
            true,
            {
                setAutoRefresh: (_, { enabled }) => enabled,
            },
        ],
        editing: [
            false,
            {
                startEditing: () => true,
                cancelEditing: () => false,
                savePipelineSuccess: () => false,
            },
        ],
        draft: [
            null as PipelineDraft | null,
            {
                setDraft: (_, { draft }) => draft,
                cancelEditing: () => null,
            },
        ],
        lastRefreshedAt: [
            null as string | null,
            {
                evaluateSuccess: () => new Date().toISOString(),
            },
        ],
    }),
    selectors({
        isNew: [() => [(_, props: PipelineLogicProps) => props.id], (id: string) => id === NEW_PIPELINE_ID],
        config: [
            (s) => [s.pipeline],
            (pipeline: MetricsPipelineApi | null): PipelineConfigApi => pipeline?.config ?? EMPTY_CONFIG,
        ],
    }),
    listeners(({ actions, props, values }) => ({
        startEditing: () => {
            actions.setDraft({
                name: values.pipeline?.name ?? '',
                description: values.pipeline?.description ?? '',
                config: values.pipeline?.config ?? EMPTY_CONFIG,
            })
        },
        setVariableValue: () => actions.evaluate(null),
        refreshTick: () => {
            if (values.autoRefreshEnabled && !values.editing && !values.evaluationLoading) {
                actions.evaluate(null)
            }
        },
        loadPipelineSuccess: () => actions.evaluate(null),
        savePipeline: async () => {
            const draft = values.draft
            if (!draft) {
                return
            }
            try {
                if (values.isNew) {
                    const created = await metricsPipelinesCreate(String(values.currentProjectId), draft)
                    lemonToast.success('Pipeline created')
                    router.actions.push(urls.metricsPipeline(created.id))
                } else {
                    await metricsPipelinesPartialUpdate(String(values.currentProjectId), props.id, draft)
                    lemonToast.success('Pipeline saved')
                    actions.savePipelineSuccess()
                    actions.loadPipeline()
                }
            } catch (error: any) {
                lemonToast.error(error.detail ?? 'The pipeline config is invalid')
            }
        },
    })),
    afterMount(({ actions, cache, props }) => {
        if (props.id === NEW_PIPELINE_ID) {
            actions.startEditing()
            return
        }
        actions.loadPipeline()
        // The disposable also pauses the poll while the tab is hidden, so a
        // backgrounded pipeline stops issuing ClickHouse queries.
        cache.disposables.add(() => {
            const intervalId = setInterval(() => actions.refreshTick(), AUTO_REFRESH_INTERVAL_MS)
            return () => clearInterval(intervalId)
        }, 'pipeline-auto-refresh')
    }),
])
