import { MarkerType, Position, type Edge as ReactFlowEdge, type Node as ReactFlowNode } from '@xyflow/react'
import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, propsChanged, reducers } from 'kea'

import { getFormattedNodes } from 'scenes/data-warehouse/scene/modeling/autolayout'

import { PipelineEdgeApi, PipelineNodeApi } from './types'

const NODE_WIDTH = 190
const NODE_HEIGHT = 110

export interface PipelineGraphLayout {
    nodes: ReactFlowNode[]
    edges: ReactFlowEdge[]
}

export interface PipelineGraphLogicProps {
    nodes: PipelineNodeApi[]
    edges: PipelineEdgeApi[]
}

export function edgeKey(edge: PipelineEdgeApi): string {
    return `${edge.source}>${edge.target}`
}

// Layout depends only on the graph's structure — health states, selection,
// and callbacks are decorated onto the laid-out nodes at render time so a
// refresh tick never retriggers the ELK pass.
async function layoutGraph(nodes: PipelineNodeApi[], edges: PipelineEdgeApi[]): Promise<PipelineGraphLayout> {
    const rfNodes: ReactFlowNode[] = nodes.map((node) => ({
        id: node.id,
        type: 'pipeline',
        position: { x: 0, y: 0 },
        width: NODE_WIDTH,
        height: NODE_HEIGHT,
        data: {
            node,
            handles: [
                { id: `target_${node.id}`, type: 'target', position: Position.Left },
                { id: `source_${node.id}`, type: 'source', position: Position.Right },
            ],
        },
    }))
    const rfEdges: ReactFlowEdge[] = edges.map((edge) => ({
        id: edgeKey(edge),
        source: edge.source,
        target: edge.target,
        sourceHandle: `source_${edge.source}`,
        targetHandle: `target_${edge.target}`,
        markerEnd: { type: MarkerType.ArrowClosed, width: 18, height: 18 },
    }))
    const laidOut = await getFormattedNodes(rfNodes as any, rfEdges, 'RIGHT')
    return { nodes: laidOut as unknown as ReactFlowNode[], edges: rfEdges }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pipelineGraphLogicValues {
    layout: PipelineGraphLayout | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pipelineGraphLogicActions {
    computeLayout: () => {
        value: true
    }
    layoutComputed: (layout: PipelineGraphLayout) => {
        layout: PipelineGraphLayout
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pipelineGraphLogicMeta {
    key: string
}

export type pipelineGraphLogicType = MakeLogicType<
    pipelineGraphLogicValues,
    pipelineGraphLogicActions,
    PipelineGraphLogicProps,
    pipelineGraphLogicMeta
>

export const pipelineGraphLogic = kea<pipelineGraphLogicType>([
    path(['products', 'metrics', 'frontend', 'pipelines', 'pipelineGraphLogic']),
    props({} as PipelineGraphLogicProps),
    key(
        (props: PipelineGraphLogicProps) =>
            `${props.nodes.map((n) => n.id).join(',')}|${props.edges.map(edgeKey).join(',')}`
    ),
    actions({
        computeLayout: true,
        layoutComputed: (layout: PipelineGraphLayout) => ({ layout }),
    }),
    reducers({
        layout: [
            null as PipelineGraphLayout | null,
            {
                layoutComputed: (_, { layout }) => layout,
            },
        ],
    }),
    listeners(({ actions, props }) => ({
        computeLayout: async (_, breakpoint) => {
            const layout = await layoutGraph(props.nodes, props.edges)
            breakpoint()
            actions.layoutComputed(layout)
        },
    })),
    propsChanged(({ actions, props }, oldProps) => {
        if (props.nodes !== oldProps.nodes || props.edges !== oldProps.edges) {
            actions.computeLayout()
        }
    }),
    afterMount(({ actions }) => {
        actions.computeLayout()
    }),
])
