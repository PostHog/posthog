import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { urlToAction } from 'kea-router'

import { productSetupStatusLogic } from 'lib/components/ProductEmptyState/productSetupStatusLogic'
import type { ProductSetupStatus } from 'lib/components/ProductEmptyState/types'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { ProductKey } from '~/queries/schema/schema-general'

import {
    autoresearchDestroy,
    autoresearchList,
    autoresearchPauseCreate,
    autoresearchResumeCreate,
} from './generated/api'
import { AutoresearchPipelineApi } from './generated/api.schemas'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface autoresearchLogicValues {
    setupStatus: ProductSetupStatus // productSetupStatusLogic
    currentTeamId: number | null // teamLogic
    mutatingPipelineIds: Record<string, boolean>
    pipelines: AutoresearchPipelineApi[]
    pipelinesLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface autoresearchLogicActions {
    setDetectedStatus: (status: ProductSetupStatus) => {
        status: ProductSetupStatus
    } // productSetupStatusLogic
    deletePipeline: (
        id: string,
        name: string
    ) => {
        id: string
        name: string
    }
    loadPipelines: () => any
    loadPipelinesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadPipelinesSuccess: (
        pipelines: AutoresearchPipelineApi[],
        payload?: any
    ) => {
        pipelines: AutoresearchPipelineApi[]
        payload?: any
    }
    pausePipeline: (pipeline: AutoresearchPipelineApi) => {
        pipeline: AutoresearchPipelineApi
    }
    resumePipeline: (pipeline: AutoresearchPipelineApi) => {
        pipeline: AutoresearchPipelineApi
    }
    setPipelineMutating: (
        id: string,
        mutating: boolean
    ) => {
        id: string
        mutating: boolean
    }
}

export type autoresearchLogicType = MakeLogicType<autoresearchLogicValues, autoresearchLogicActions>

export const autoresearchLogic = kea<autoresearchLogicType>([
    path(['products', 'autoresearch', 'autoresearchLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            productSetupStatusLogic({ productKey: ProductKey.AUTORESEARCH }),
            ['status as setupStatus'],
        ],
        actions: [productSetupStatusLogic({ productKey: ProductKey.AUTORESEARCH }), ['setDetectedStatus']],
    })),
    actions({
        deletePipeline: (id: string, name: string) => ({ id, name }),
        pausePipeline: (pipeline: AutoresearchPipelineApi) => ({ pipeline }),
        resumePipeline: (pipeline: AutoresearchPipelineApi) => ({ pipeline }),
        setPipelineMutating: (id: string, mutating: boolean) => ({ id, mutating }),
    }),
    reducers({
        mutatingPipelineIds: [
            {} as Record<string, boolean>,
            {
                setPipelineMutating: (
                    state: Record<string, boolean>,
                    { id, mutating }: { id: string; mutating: boolean }
                ) => ({ ...state, [id]: mutating }),
            },
        ],
    }),
    loaders(({ values }) => ({
        pipelines: [
            [] as AutoresearchPipelineApi[],
            {
                loadPipelines: async () => {
                    if (!values.currentTeamId) {
                        return []
                    }
                    const response = await autoresearchList(String(values.currentTeamId))
                    return response.results
                },
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        // Detection for the scene empty-state gate: this is a creation-first product,
        // so "set up" simply means at least one pipeline exists.
        loadPipelinesSuccess: ({ pipelines }: { pipelines: AutoresearchPipelineApi[] }) => {
            actions.setDetectedStatus(pipelines.length > 0 ? 'has-data' : 'needs-setup')
        },
        loadPipelinesFailure: () => {
            // Never strand the gate on its spinner: with no earlier answer, fail open
            // to the real scene. Don't downgrade an existing answer on a reload blip.
            if (values.setupStatus === 'loading') {
                actions.setDetectedStatus('unknown')
            }
        },
        deletePipeline: async ({ id, name }: { id: string; name: string }) => {
            if (!values.currentTeamId) {
                return
            }
            actions.setPipelineMutating(id, true)
            try {
                await autoresearchDestroy(String(values.currentTeamId), id)
                lemonToast.success(`Deleted "${name}"`)
                actions.loadPipelines()
            } catch (error: any) {
                lemonToast.error(error?.detail ?? error?.data?.detail ?? 'Failed to delete the model')
            } finally {
                actions.setPipelineMutating(id, false)
            }
        },
        pausePipeline: async ({ pipeline }: { pipeline: AutoresearchPipelineApi }) => {
            if (!values.currentTeamId) {
                return
            }
            actions.setPipelineMutating(pipeline.id, true)
            try {
                await autoresearchPauseCreate(String(values.currentTeamId), pipeline.id)
                lemonToast.success(`Paused "${pipeline.name}". Daily scoring is on hold.`)
                actions.loadPipelines()
            } catch (error: any) {
                lemonToast.error(error?.detail ?? error?.data?.detail ?? 'Failed to pause the model')
            } finally {
                actions.setPipelineMutating(pipeline.id, false)
            }
        },
        resumePipeline: async ({ pipeline }: { pipeline: AutoresearchPipelineApi }) => {
            if (!values.currentTeamId) {
                return
            }
            actions.setPipelineMutating(pipeline.id, true)
            try {
                await autoresearchResumeCreate(String(values.currentTeamId), pipeline.id)
                lemonToast.success(`Resumed "${pipeline.name}"`)
                actions.loadPipelines()
            } catch (error: any) {
                lemonToast.error(error?.detail ?? error?.data?.detail ?? 'Failed to resume the model')
            } finally {
                actions.setPipelineMutating(pipeline.id, false)
            }
        },
    })),
    urlToAction(({ actions }) => ({
        // Reload whenever the list route is entered — the scene logic can stay mounted across
        // navigation (e.g. returning from the create flow), so afterMount alone leaves the list
        // showing a stale snapshot that omits a just-created pipeline.
        [urls.autoresearch()]: () => {
            actions.loadPipelines()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadPipelines()
    }),
])
