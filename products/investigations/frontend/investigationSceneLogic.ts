export type investigationSceneLogicType = MakeLogicType<
    investigationSceneLogicValues,
    investigationSceneLogicActions,
    InvestigationSceneProps,
    investigationSceneLogicMeta
>

export const investigationSceneLogic = kea<investigationSceneLogicType>([
    props({} as InvestigationSceneProps),
    key(({ id }) => id),
    path((key) => ['products', 'investigations', 'investigationSceneLogic', key]),
    actions({
        loadInvestigation: true,
        loaded: (record: SavedInvestigationApi) => ({ record }),
        changeDocument: (document: InvestigationDocument) => ({ document }),
        setBusy: (busy: boolean) => ({ busy }),
        setError: (error: string | null, conflict: boolean = false) => ({ error, conflict }),
        save: true,
        saved: (record: SavedInvestigationApi, document: InvestigationDocument) => ({ record, document }),
        saveCopy: true,
        archive: true,
        discard: true,
    }),
    reducers({
        record: [
            null as SavedInvestigationApi | null,
            { loaded: (_, { record }) => record, saved: (_, { record }) => record },
        ],
        document: [
            null as InvestigationDocument | null,
            {
                loaded: (_, { record }) => investigationDocumentSchema.parse(record.document),
                changeDocument: (_, { document }) => document,
            },
        ],
        savedDocument: [
            null as InvestigationDocument | null,
            {
                loaded: (_, { record }) => investigationDocumentSchema.parse(record.document),
                saved: (_, { document }) => document,
            },
        ],
        loading: [true, { loadInvestigation: () => true, loaded: () => false, setError: () => false }],
        busy: [false, { setBusy: (_, { busy }) => busy }],
        error: [null as string | null, { setError: (_, { error }) => error, loaded: () => null, saved: () => null }],
        conflict: [false, { setError: (_, { conflict }) => conflict, loaded: () => false, saved: () => false }],
        discarded: [false, { discard: () => true, changeDocument: () => false }],
    }),
    selectors({
        dirty: [
            (s) => [s.document, s.savedDocument, s.discarded],
            (
                document: InvestigationDocument | null,
                savedDocument: InvestigationDocument | null,
                discarded: boolean
            ): boolean =>
                !discarded &&
                !!document &&
                !!savedDocument &&
                JSON.stringify(document) !== JSON.stringify(savedDocument),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        loadInvestigation: async (_, breakpoint) => {
            try {
                const record = await investigationsRetrieve(String(teamLogic.values.currentTeamId), props.id)
                breakpoint()
                investigationDocumentSchema.parse(record.document)
                actions.loaded(record)
            } catch (error) {
                breakpoint()
                actions.setError(
                    error instanceof ApiError && error.status === 404
                        ? 'This investigation was archived or is not available in this project.'
                        : 'Could not load this investigation. Try again. Your saved content has not been replaced.'
                )
            }
        },
        save: async (_, breakpoint) => {
            if (values.busy || !values.document || !values.record || values.conflict) {
                return
            }
            const document = values.document
            actions.setBusy(true)
            try {
                const record = await investigationsPartialUpdate(String(teamLogic.values.currentTeamId), props.id, {
                    document,
                    revision: values.record.revision,
                })
                breakpoint()
                actions.saved(record, document)
                posthog.capture('investigation saved', {
                    evidence_count: document.evidence.length,
                    run_count: document.runs.length,
                })
            } catch (error) {
                breakpoint()
                const conflict = error instanceof ApiError && error.status === 409
                actions.setError(
                    conflict
                        ? 'Someone saved a newer version. Save a copy to keep your changes, or reload the latest version.'
                        : 'Could not save your investigation. Your changes are still here. Try again.',
                    conflict
                )
            } finally {
                actions.setBusy(false)
            }
        },
        saveCopy: async (_, breakpoint) => {
            if (values.busy || !values.document) {
                return
            }
            actions.setBusy(true)
            try {
                const record = await investigationsCreate(String(teamLogic.values.currentTeamId), {
                    document: values.document,
                })
                breakpoint()
                actions.discard()
                router.actions.push(urls.investigation(record.id))
            } catch {
                breakpoint()
                actions.setError('Could not save a copy. Try again.', values.conflict)
            } finally {
                actions.setBusy(false)
            }
        },
        archive: async (_, breakpoint) => {
            if (values.busy || !values.record) {
                return
            }
            actions.setBusy(true)
            try {
                await investigationsPartialUpdate(String(teamLogic.values.currentTeamId), props.id, {
                    revision: values.record.revision,
                    deleted: true,
                })
                breakpoint()
                actions.discard()
                router.actions.push(urls.investigations())
            } catch (error) {
                breakpoint()
                const conflict = error instanceof ApiError && error.status === 409
                actions.setError(
                    conflict
                        ? 'Someone saved a newer version. Reload it before archiving.'
                        : 'Could not archive this investigation. Try again.',
                    conflict
                )
            } finally {
                actions.setBusy(false)
            }
        },
    })),
    beforeUnload(({ values }) => ({
        enabled: () => values.dirty,
        message: 'Leave this investigation? Your unsaved changes will be discarded.',
    })),
    afterMount(({ actions }) => actions.loadInvestigation()),
])
