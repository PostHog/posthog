import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { beforeUnload, router } from 'kea-router'
import posthog from 'posthog-js'

import { ApiError } from 'lib/api-error'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { investigationsCreate, investigationsPartialUpdate, investigationsRetrieve } from './generated/api'
import { SavedInvestigationApi } from './generated/api.schemas'
import { InvestigationDocument, investigationDocumentSchema } from './investigationDocument'

