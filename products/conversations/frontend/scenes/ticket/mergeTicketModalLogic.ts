export const mergeTicketModalLogic = kea<mergeTicketModalLogicType>([
    path(['products', 'conversations', 'frontend', 'scenes', 'ticket', 'mergeTicketModalLogic']),
    props({ sourceTicket: {} as Ticket, onMerged: () => {} } as MergeTicketModalLogicProps),
    key((props) => props.sourceTicket.id || 'new'),
    actions({
        openMergeModal: true,
        closeMergeModal: true,
        setSearchQuery: (query: string) => ({ query }),
        setSelectedTargetId: (id: string | null) => ({ id }),
        setSourceNote: (note: string) => ({ note }),
        setTargetNote: (note: string) => ({ note }),
        setSourceSendToCustomer: (value: boolean) => ({ value }),
        setTargetSendToCustomer: (value: boolean) => ({ value }),
        setAcknowledgedCrossCustomer: (value: boolean) => ({ value }),
        submitMerge: true,
        submitMergeDone: true,
        loadSourceMessages: true,
        loadTargetMessages: true,
        addTargetOption: (ticket: Ticket) => ({ ticket }),
    }),
    reducers({
        isOpen: [
            false,
            {
                openMergeModal: () => true,
                closeMergeModal: () => false,
            },
        ],
        searchQuery: [
            '',
            {
                setSearchQuery: (_, { query }) => query,
                openMergeModal: () => '',
                closeMergeModal: () => '',
            },
        ],
        selectedTargetId: [
            null as string | null,
            {
                setSelectedTargetId: (_, { id }) => id,
                openMergeModal: () => null,
                closeMergeModal: () => null,
            },
        ],
        // Targets not in the suggestion/search lists (e.g. the root ticket we redirect to after a
        // rule-1 conflict) so selectedTarget can still resolve them.
        extraTargets: [
            [] as Ticket[],
            {
                addTargetOption: (state: Ticket[], { ticket }) =>
                    state.some((t) => t.id === ticket.id) ? state : [...state, ticket],
                openMergeModal: () => [],
                closeMergeModal: () => [],
            },
        ],
        sourceNote: [
            '',
            {
                setSourceNote: (_, { note }) => note,
                openMergeModal: () => '',
                closeMergeModal: () => '',
            },
        ],
        targetNote: [
            '',
            {
                setTargetNote: (_, { note }) => note,
                openMergeModal: () => '',
                closeMergeModal: () => '',
            },
        ],
        sourceSendToCustomer: [
            false,
            {
                setSourceSendToCustomer: (_, { value }) => value,
                openMergeModal: () => false,
                closeMergeModal: () => false,
            },
        ],
        targetSendToCustomer: [
            false,
            {
                setTargetSendToCustomer: (_, { value }) => value,
                openMergeModal: () => false,
                closeMergeModal: () => false,
            },
        ],
        acknowledgedCrossCustomer: [
            false,
            {
                setAcknowledgedCrossCustomer: (_, { value }) => value,
                // A new target may belong to a different customer, so the prior acknowledgment no longer applies.
                setSelectedTargetId: () => false,
                openMergeModal: () => false,
                closeMergeModal: () => false,
            },
        ],
        submitting: [
            false,
            {
                submitMerge: () => true,
                submitMergeDone: () => false,
                openMergeModal: () => false,
                closeMergeModal: () => false,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        suggestedTickets: [
            [] as Ticket[],
            {
                loadSuggestedTickets: async (): Promise<Ticket[]> => {
                    const distinctIds = props.sourceTicket.person?.distinct_ids?.length
                        ? props.sourceTicket.person.distinct_ids
                        : props.sourceTicket.distinct_id
                          ? [props.sourceTicket.distinct_id]
                          : []
                    if (distinctIds.length === 0) {
                        return []
                    }
                    try {
                        const response = await api.conversationsTickets.list({
                            distinct_ids: distinctIds.join(','),
                            order_by: '-last_message_at',
                            limit: 20,
                        })
                        return (response.results || []).filter(
                            (t: Ticket) => t.id !== props.sourceTicket.id && !t.merged_into_id
                        )
                    } catch {
                        return []
                    }
                },
            },
        ],
        searchResults: [
            [] as Ticket[],
            {
                loadSearchResults: async ({ query }, breakpoint): Promise<Ticket[]> => {
                    await breakpoint(300)
                    if (!query.trim()) {
                        return values.searchResults
                    }
                    try {
                        const response = await api.conversationsTickets.list({
                            search: query,
                            order_by: '-last_message_at',
                            limit: 20,
                        })
                        breakpoint()
                        // Merged tickets stay searchable so the user can pick one and be redirected
                        // to its root (rule 1); only the current ticket is excluded outright.
                        return (response.results || []).filter((t: Ticket) => t.id !== props.sourceTicket.id)
                    } catch {
                        return []
                    }
                },
            },
        ],
        sourceMessages: [
            [] as CommentType[],
            {
                loadSourceMessages: async (): Promise<CommentType[]> => {
                    try {
                        const response = await api.comments.list({
                            scope: 'conversations_ticket',
                            item_id: props.sourceTicket.id,
                        })
                        return (response.results || []).reverse()
                    } catch {
                        return []
                    }
                },
            },
        ],
        targetMessages: [
            [] as CommentType[],
            {
                loadTargetMessages: async (): Promise<CommentType[]> => {
                    const targetId = values.selectedTargetId
                    if (!targetId) {
                        return []
                    }
                    try {
                        const response = await api.comments.list({
                            scope: 'conversations_ticket',
                            item_id: targetId,
                        })
                        return (response.results || []).reverse()
                    } catch {
                        return []
                    }
                },
            },
        ],
    })),
    selectors(({ props }) => ({
        targetOptions: [
            (s) => [s.searchQuery, s.suggestedTickets, s.searchResults],
            (searchQuery: string, suggestedTickets: Ticket[], searchResults: Ticket[]): Ticket[] =>
                searchQuery.trim() ? searchResults : suggestedTickets,
        ],
        selectedTarget: [
            (s) => [s.selectedTargetId, s.suggestedTickets, s.searchResults, s.extraTargets],
            (
                selectedTargetId: string | null,
                suggestedTickets: Ticket[],
                searchResults: Ticket[],
                extraTargets: Ticket[]
            ): Ticket | null =>
                selectedTargetId
                    ? ([...suggestedTickets, ...searchResults, ...extraTargets].find(
                          (t) => t.id === selectedTargetId
                      ) ?? null)
                    : null,
        ],
        isCrossCustomer: [
            (s) => [s.selectedTarget],
            (selectedTarget: Ticket | null): boolean =>
                selectedTarget ? !isSameCustomer(props.sourceTicket, selectedTarget) : false,
        ],
        sourceChatMessages: [
            (s) => [s.sourceMessages],
            (sourceMessages: CommentType[]): ChatMessage[] =>
                sourceMessages.map((m) => commentToChatMessage(m, props.sourceTicket)),
        ],
        targetChatMessages: [
            (s) => [s.targetMessages, s.selectedTarget],
            (targetMessages: CommentType[], selectedTarget: Ticket | null): ChatMessage[] =>
                targetMessages.map((m) => commentToChatMessage(m, selectedTarget)),
        ],
    })),
    listeners(({ actions, props, values }) => ({
        openMergeModal: () => {
            actions.loadSuggestedTickets()
            actions.loadSourceMessages()
        },
        setSearchQuery: ({ query }) => {
            if (query.trim()) {
                actions.loadSearchResults({ query })
            }
        },
        setSelectedTargetId: ({ id }) => {
            if (id) {
                actions.loadTargetMessages()
            }
        },
        submitMerge: async () => {
            const target = values.selectedTarget
            if (!target) {
                lemonToast.error('Select a ticket to merge into.')
                actions.submitMergeDone()
                return
            }
            if (values.isCrossCustomer && !values.acknowledgedCrossCustomer) {
                lemonToast.error('Confirm the customers differ before merging.')
                actions.submitMergeDone()
                return
            }
            try {
                await conversationsTicketsMergeCreate(String(getCurrentTeamId()), props.sourceTicket.id, {
                    target_ticket_id: target.id,
                    source_note: values.sourceNote || undefined,
                    source_is_private: !values.sourceSendToCustomer,
                    target_note: values.targetNote || undefined,
                    target_is_private: !values.targetSendToCustomer,
                })
                lemonToast.success(`Merged into #${target.ticket_number}`)
                actions.closeMergeModal()
                props.onMerged()
            } catch (error: unknown) {
                const err = (error && typeof error === 'object' ? error : {}) as {
                    detail?: string
                    error_type?: string
                    root_ticket_id?: string
                    root_ticket_number?: number
                }
                // Rule 1: the target was already merged into a root ticket. Point the user at the
                // root — pull it in as a selectable target and switch to it, but don't merge yet.
                if (err.error_type === 'target_already_merged' && err.root_ticket_id) {
                    try {
                        const root = await api.conversationsTickets.get(err.root_ticket_id)
                        actions.addTargetOption(root)
                        actions.setSelectedTargetId(root.id)
                        lemonToast.info(
                            `That ticket is already merged into #${err.root_ticket_number}. Switched the target to #${err.root_ticket_number} — review and merge again.`
                        )
                    } catch {
                        lemonToast.error(err.detail || 'Failed to merge ticket.')
                    }
                } else {
                    lemonToast.error(err.detail || 'Failed to merge ticket.')
                }
            } finally {
                actions.submitMergeDone()
            }
        },
    })),
])
