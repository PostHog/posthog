/** Two tickets are the same customer if they share a person, distinct_id, or sender email. */
export function isSameCustomer(a: Ticket, b: Ticket): boolean {
    if (a.person?.id && b.person?.id) {
        return a.person.id === b.person.id
    }
    if (a.distinct_id && b.distinct_id) {
        return a.distinct_id === b.distinct_id
    }
    if (a.email_from && b.email_from) {
        return a.email_from.toLowerCase() === b.email_from.toLowerCase()
    }
    return false
}

/** Short human label for a ticket's customer, used in the cross-customer confirmation. */
export function customerLabel(ticket: Ticket): string {
    return ticket.person?.name || ticket.email_from || ticket.distinct_id || 'Unknown customer'
}

