import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { router, urlToAction } from 'kea-router'

import { ApiConfig } from 'lib/api'
import { type SupportFormFields, supportLogic } from 'lib/components/Support/supportLogic'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { urls } from 'scenes/urls'

import { sidepanelTicketsLogic } from '../../components/SidePanel/sidepanelTicketsLogic'
import { posthogSupportDraftsRetrieve } from '../../generated/api'
import type { PostHogSupportDraftApi } from '../../generated/api.schemas'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface myTicketsSceneLogicValues {
    isReviewingDraft: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface myTicketsSceneLogicActions {
    loadTickets: () => {
        value: true
    } // sidepanelTicketsLogic
    closeSupportForm: () => {
        value: true
    } // supportLogic
    resetSendSupportRequest: (values?: SupportFormFields | undefined) => {
        values?: SupportFormFields
    } // supportLogic
    closeDraftReview: () => {
        value: true
    }
    openSupportDraft: (draftId: string) => {
        draftId: string
    }
    reviewDraft: (draft: PostHogSupportDraftApi) => {
        draft: PostHogSupportDraftApi
    }
}

export type myTicketsSceneLogicType = MakeLogicType<myTicketsSceneLogicValues, myTicketsSceneLogicActions>

// sidepanelTicketsLogic stays mounted for the whole session (the side panel tab icon reads its
// unread count), so its own initial load runs once at app boot and never again. This scene-scoped
// logic exists to refetch on every navigation to the tickets scene, the same way the side panel
// refetches each time it opens.
export const myTicketsSceneLogic = kea<myTicketsSceneLogicType>([
    path(['products', 'conversations', 'frontend', 'scenes', 'myTickets', 'myTicketsSceneLogic']),
    connect(() => ({
        actions: [
            sidepanelTicketsLogic,
            ['loadTickets'],
            supportLogic,
            ['closeSupportForm', 'resetSendSupportRequest'],
        ],
    })),
    actions({
        openSupportDraft: (draftId: string) => ({ draftId }),
        reviewDraft: (draft: PostHogSupportDraftApi) => ({ draft }),
        closeDraftReview: true,
    }),
    reducers({
        // Its own modal, because the shared support modal stays hidden wherever the side panel is
        // available, which includes this scene.
        isReviewingDraft: [
            false,
            {
                reviewDraft: () => true,
                closeDraftReview: () => false,
                closeSupportForm: () => false,
            },
        ],
    }),
    listeners(({ actions }) => ({
        openSupportDraft: async ({ draftId }) => {
            let draft: PostHogSupportDraftApi | null = null
            try {
                draft = await posthogSupportDraftsRetrieve(String(ApiConfig.getCurrentProjectId()), draftId)
            } catch (e) {
                if ((e as { status?: number }).status !== 404) {
                    // Keep the link as it is, so a reload retries a draft that may still be there
                    lemonToast.error("Couldn't load the draft. Reload the page to try again.")
                    return
                }
                lemonToast.error('This draft has expired or was already sent. Ask your agent to draft it again.')
            }
            const { support_draft: _, ...searchParams } = router.values.searchParams
            router.actions.replace(router.values.location.pathname, searchParams, router.values.hashParams)
            if (!draft) {
                return
            }
            actions.resetSendSupportRequest({
                name: '',
                email: '',
                kind: 'support',
                message: draft.message,
                ticket_context: draft.ticket_context,
                ai_draft_id: draft.id,
            })
            actions.reviewDraft(draft)
        },
        closeDraftReview: () => {
            actions.resetSendSupportRequest()
        },
    })),
    urlToAction(({ actions }) => ({
        [urls.myTickets()]: (_, searchParams) => {
            if (typeof searchParams.support_draft === 'string') {
                actions.openSupportDraft(searchParams.support_draft)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadTickets()
    }),
])
