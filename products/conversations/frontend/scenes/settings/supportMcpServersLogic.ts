export interface supportMcpServersLogicValues {
    agentServerAccessLoadingKeys: Set<string> // mcpGatewayLogic
    canManageAgentAccess: boolean // mcpGatewayLogic
    currentUserId: number | null // mcpGatewayLogic
    servers: MCPGatewayServerApi[] // mcpGatewayLogic
    serversLoading: boolean // mcpGatewayLogic
    serviceAccounts: MCPServiceAccountApi[] // mcpGatewayLogic
    serviceAccountsLoading: boolean // mcpGatewayLogic
    showAllServers: boolean
    supportAccount: MCPServiceAccountApi | null
    supportMcpLoading: boolean
    supportServerRows: SupportMcpServerRow[]
}

