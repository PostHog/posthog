export const supportMcpServersLogic = kea<supportMcpServersLogicType>([
    path(['products', 'conversations', 'frontend', 'scenes', 'settings', 'supportMcpServersLogic']),
    connect(() => ({
        values: [
            mcpGatewayLogic,
            [
                'agentServerAccessLoadingKeys',
                'canManageAgentAccess',
                'currentUserId',
                'servers',
                'serversInitialized',
                'serviceAccounts',
                'serviceAccountsInitialized',
            ],
        ],
        actions: [mcpGatewayLogic, ['setAgentServerAccess']],
    })),
    actions({
        setShowAllServers: (showAll: boolean) => ({ showAll }),
    }),
    reducers({
        showAllServers: [false, { setShowAllServers: (_, { showAll }) => showAll }],
    }),
    selectors({
        supportAccount: [
            (s) => [s.serviceAccounts],
            (serviceAccounts: MCPServiceAccountApi[]): MCPServiceAccountApi | null =>
                serviceAccounts.find((account) => account.agent_key === 'support') ?? null,
        ],
        // Servers and service accounts load in parallel; rows built before both have landed
        // would attribute shares wrongly (a missing support account reads as "not shared").
        // Initialized flags rather than loading flags, so re-loads after a share toggle don't
        // blank the card back to a spinner.
        supportMcpInitialized: [
            (s) => [s.serversInitialized, s.serviceAccountsInitialized],
            (serversInitialized: boolean, serviceAccountsInitialized: boolean): boolean =>
                serversInitialized && serviceAccountsInitialized,
        ],
        // Support runs are personless, so only team-scoped grants back them. The rows keep
        // teammates' personal grants invisible: they never back a support reply, and showing
        // them would read as coverage the agent doesn't have.
        supportServerRows: [
            (s) => [s.servers, s.supportAccount, s.currentUserId, s.canManageAgentAccess],
            (
                servers: MCPGatewayServerApi[],
                supportAccount: MCPServiceAccountApi | null,
                currentUserId: number | null,
                canManageAgentAccess: boolean
            ): SupportMcpServerRow[] =>
                servers
                    .filter((server) => server.is_team_enabled)
                    .map((server) => {
                        const share = agentServerShare(supportAccount, server.id, currentUserId)
                        const yourGrant =
                            currentUserId === null
                                ? undefined
                                : supportAccount?.servers.find(
                                      (grant) => grant.id === server.id && grant.shared_by.id === currentUserId
                                  )
                        return {
                            server,
                            share,
                            sharedWithTeamByYou: share.sharedByYou && share.yourScope === 'team',
                            yourGrantState: yourGrant?.connection_state ?? null,
                            shareDisabledReason: shareDisabledReason(
                                server,
                                share,
                                supportAccount,
                                canManageAgentAccess
                            ),
                        }
                    })
                    .filter(
                        ({ server, share }) =>
                            server.your_connection !== null || share.sharedByYou || share.teamSharedByOthers.length > 0
                    )
                    .sort((a, b) => a.server.name.localeCompare(b.server.name)),
        ],
    }),
])
