import {
    AgentServerShare,
    agentServerShare,
    mcpGatewayLogic,
} from '@posthog/products-mcp-store/frontend/gateway/mcpGatewayLogic'
import type {
    ConnectionStateEnumApi,
    MCPAgentGrantScopeEnumApi,
    MCPGatewayServerApi,
    MCPServiceAccountApi,
} from '@posthog/products-mcp-store/frontend/generated/api.schemas'

export interface SupportMcpServerRow {
    server: MCPGatewayServerApi
    share: AgentServerShare
    /** Your grant is team-scoped, so autonomous support replies can use your connection. */
    sharedWithTeamByYou: boolean
    /** Health of the credential behind your grant, null when you have no grant. */
    yourGrantState: ConnectionStateEnumApi | null
}

