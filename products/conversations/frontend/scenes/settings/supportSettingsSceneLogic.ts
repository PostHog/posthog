import { MakeLogicType, kea, listeners, path } from 'kea'
import { router } from 'kea-router'

import { settingsLogic } from 'scenes/settings/settingsLogic'
import { SettingId } from 'scenes/settings/types'

export const CONVERSATIONS_LOGIC_KEY = 'conversationsSettings'

const VALID_SETTING_IDS = new Set<SettingId>([
    'conversations-general',
    'conversations-channels',
    'conversations-ai',
    'conversations-learn-from-support',
    'conversations-notifications',
    'conversations-imports',
    'conversations-macros',
])

const DEFAULT_SETTING_ID: SettingId = 'conversations-general'

export function resolveSettingId(hashParams: Record<string, any>): SettingId {
    const candidate = hashParams.selectedSetting
    const hasNoSection = typeof candidate !== 'string' || !VALID_SETTING_IDS.has(candidate as SettingId)
    if (hashParams.channel && (hasNoSection || candidate === DEFAULT_SETTING_ID)) {
        return 'conversations-channels'
    }
    if (!hasNoSection) {
        return candidate as SettingId
    }
    return DEFAULT_SETTING_ID
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export type supportSettingsSceneLogicType = MakeLogicType<{}, {}>

export const supportSettingsSceneLogic = kea<supportSettingsSceneLogicType>([
    path(['products', 'conversations', 'frontend', 'scenes', 'settings', 'supportSettingsSceneLogic']),
    listeners(() => ({
        // This builds the settings pane before <Settings> renders, and its selectedSettingId
        // only reads settingId on build, so pass the section the URL asks for.
        [settingsLogic({
            logicKey: CONVERSATIONS_LOGIC_KEY,
            sectionId: 'environment-conversations',
            settingId: resolveSettingId(router.values.hashParams),
        }).actionTypes.selectSetting]: ({ setting }: { setting: string }) => {
            const { channel, ...hashParams } = router.values.hashParams
            if (channel && setting !== 'conversations-channels') {
                router.actions.replace(router.values.location.pathname, router.values.searchParams, {
                    ...hashParams,
                    selectedSetting: setting,
                })
            }
        },
    })),
])
