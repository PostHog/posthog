export const intercomImportLogic = kea<intercomImportLogicType>([
    path(['products', 'conversations', 'frontend', 'scenes', 'settings', 'intercomImportLogic']),
    connect(() => ({
        values: [supportSettingsLogic, ['emailConfigs']],
        actions: [supportSettingsLogic, ['loadEmailConfigs']],
    })),
    actions({
        setRegion: (region: IntercomRegion) => ({ region }),
        setAccessToken: (accessToken: string) => ({ accessToken }),
        setEmailChannelId: (emailChannelId: string | null) => ({ emailChannelId }),
        submitImport: true,
        startPolling: true,
        stopPolling: true,
    }),
    reducers({
        region: ['us' as IntercomRegion, { setRegion: (_, { region }) => region }],
        accessToken: ['', { setAccessToken: (_, { accessToken }) => accessToken }],
        emailChannelId: [null as string | null, { setEmailChannelId: (_, { emailChannelId }) => emailChannelId }],
    }),
    loaders(({ values }) => ({
        importJob: [
            null as IntercomImportJobApi | null,
            {
                loadImportJob: async () => {
                    try {
                        return await conversationsIntercomImportsStatusRetrieve(String(getCurrentTeamId()))
                    } catch (error: any) {
                        if (error?.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
                submitImport: async () => {
                    return await conversationsIntercomImportsCreate(String(getCurrentTeamId()), {
                        region: values.region,
                        access_token: values.accessToken,
                        default_email_channel_id: values.emailChannelId,
                    })
                },
            },
        ],
    })),
    selectors({
        isImportRunning: [
            // Derive from job status only: the loaders flag is also true during the initial status GET.
            (s) => [s.importJob],
            (importJob: IntercomImportJobApi | null): boolean =>
                importJob?.status === 'running' || importJob?.status === 'pending',
        ],
        importProgressLabel: [
            (s) => [s.importJob],
            (importJob: IntercomImportJobApi | null): string | null => {
                if (!importJob || (importJob.status !== 'running' && importJob.status !== 'pending')) {
                    return null
                }
                if (importJob.total_conversations > 0) {
                    return `${importJob.processed_conversations.toLocaleString()} / ${importJob.total_conversations.toLocaleString()}`
                }
                return `${importJob.processed_conversations.toLocaleString()} processed`
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        submitImportSuccess: () => {
            lemonToast.success('Intercom import started')
            actions.setAccessToken('')
            actions.startPolling()
        },
        submitImportFailure: ({ error }) => {
            lemonToast.error(error || 'Failed to start Intercom import')
        },
        startPolling: () => {
            actions.loadImportJob()
            cache.isPolling = true
            cache.disposables.add(() => {
                const pollTimerId = window.setInterval(() => actions.loadImportJob(), POLL_INTERVAL_MS)
                return () => clearInterval(pollTimerId)
            }, 'pollImportJob')
        },
        loadImportJobSuccess: ({ importJob }) => {
            // Only while the token is empty, so a poll refresh can't change the region under the user.
            if (importJob?.region && !values.accessToken) {
                actions.setRegion(importJob.region)
            }
            if (importJob && TERMINAL_STATUSES.includes(importJob.status)) {
                actions.stopPolling()
            } else if (importJob && (importJob.status === 'running' || importJob.status === 'pending')) {
                if (!cache.isPolling) {
                    actions.startPolling()
                }
            }
        },
        stopPolling: () => {
            cache.isPolling = false
            cache.disposables.dispose('pollImportJob')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadImportJob()
        actions.loadEmailConfigs()
    }),
])
