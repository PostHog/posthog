import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { getCurrentTeamId } from 'lib/utils/getAppContext'

import { conversationsIntercomImportsCreate, conversationsIntercomImportsStatusRetrieve } from '../../generated/api'
import type { IntercomImportJobApi, IntercomImportStartApi } from '../../generated/api.schemas'
import { supportSettingsLogic } from './supportSettingsLogic'
import type { EmailConfigStatus } from './supportSettingsLogic'

export type IntercomImportJobStatus = IntercomImportJobApi['status']
export type IntercomRegion = NonNullable<IntercomImportStartApi['region']>

const TERMINAL_STATUSES: IntercomImportJobStatus[] = ['completed', 'failed']
const POLL_INTERVAL_MS = 3000

