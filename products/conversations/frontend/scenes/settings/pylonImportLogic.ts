// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pylonImportLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        isImportRunning: (importJob: PylonImportJobApi | null) => boolean
        importProgressLabel: (importJob: PylonImportJobApi | null) => string | null
    }
}

export type pylonImportLogicType = MakeLogicType<
    pylonImportLogicValues,
    pylonImportLogicActions,
    Record<string, any>,
    pylonImportLogicMeta
>

export const pylonImportLogic = kea<pylonImportLogicType>([
    path(['products', 'conversations', 'frontend', 'scenes', 'settings', 'pylonImportLogic']),
    connect(() => ({
        values: [supportSettingsLogic, ['emailConfigs']],
        actions: [supportSettingsLogic, ['loadEmailConfigs']],
    })),
    actions({
        setApiToken: (apiToken: string) => ({ apiToken }),
        setEmailChannelId: (emailChannelId: string | null) => ({ emailChannelId }),
        submitImport: true,
        startPolling: true,
        stopPolling: true,
    }),
    reducers({
        apiToken: ['', { setApiToken: (_, { apiToken }) => apiToken }],
        emailChannelId: [null as string | null, { setEmailChannelId: (_, { emailChannelId }) => emailChannelId }],
    }),
    loaders(({ values }) => ({
        importJob: [
            null as PylonImportJobApi | null,
            {
                loadImportJob: async () => {
                    try {
                        return await conversationsPylonImportsStatusRetrieve(String(getCurrentTeamId()))
                    } catch (error: any) {
                        if (error?.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
                submitImport: async () => {
                    return await conversationsPylonImportsCreate(String(getCurrentTeamId()), {
                        api_token: values.apiToken,
                        default_email_channel_id: values.emailChannelId,
                    })
                },
            },
        ],
    })),
    selectors({
        isImportRunning: [
            // Derive from job status only: the loaders flag is also true during the initial status GET.
            (s) => [s.importJob],
            (importJob: PylonImportJobApi | null): boolean =>
                importJob?.status === 'running' || importJob?.status === 'pending',
        ],
        importProgressLabel: [
            (s) => [s.importJob],
            (importJob: PylonImportJobApi | null): string | null => {
                if (!importJob || (importJob.status !== 'running' && importJob.status !== 'pending')) {
                    return null
                }
                if (importJob.total_issues > 0) {
                    return `${importJob.processed_issues.toLocaleString()} / ${importJob.total_issues.toLocaleString()}`
                }
                return `${importJob.processed_issues.toLocaleString()} processed`
            },
        ],
    }),
    listeners(({ actions, cache }) => ({
        submitImportSuccess: () => {
            lemonToast.success('Pylon import started')
            actions.setApiToken('')
            actions.startPolling()
        },
        submitImportFailure: ({ error }) => {
            lemonToast.error(error || 'Failed to start Pylon import')
            // The server can keep the job when it cannot tell whether the import started.
            actions.loadImportJob()
        },
        startPolling: () => {
            actions.loadImportJob()
            cache.isPolling = true
            cache.disposables.add(() => {
                const pollTimerId = window.setInterval(() => actions.loadImportJob(), POLL_INTERVAL_MS)
                return () => clearInterval(pollTimerId)
            }, 'pollImportJob')
        },
        loadImportJobSuccess: ({ importJob }) => {
            if (importJob && TERMINAL_STATUSES.includes(importJob.status)) {
                actions.stopPolling()
            } else if (importJob && (importJob.status === 'running' || importJob.status === 'pending')) {
                if (!cache.isPolling) {
                    actions.startPolling()
                }
            }
        },
        stopPolling: () => {
            cache.isPolling = false
            cache.disposables.dispose('pollImportJob')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadImportJob()
        actions.loadEmailConfigs()
    }),
])
