export type supportTagsLogicType = MakeLogicType<supportTagsLogicValues, supportTagsLogicActions>

export const supportTagsLogic = kea<supportTagsLogicType>([
    path(['products', 'conversations', 'frontend', 'scenes', 'settings', 'supportTagsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
        actions: [tagsModel, ['refreshTags']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
    }),
    loaders(({ values, actions }) => ({
        tags: [
            null as TagUsageApi[] | null,
            {
                loadTags: async () => {
                    const response = await tagsUsageList(String(values.currentProjectId), {
                        limit: TAG_PAGE_SIZE,
                        ...(values.search ? { search: values.search } : {}),
                    })
                    return response.results
                },
                renameTag: async ({ tag, name }: { tag: TagUsageApi; name: string }) => {
                    const renamed = await tagsPartialUpdate(String(values.currentProjectId), tag.id, { name })
                    lemonToast.success(`Renamed to "${renamed.name}"`)
                    actions.refreshTags()
                    return (values.tags ?? []).map((existing) => (existing.id === tag.id ? renamed : existing))
                },
                deleteTag: async ({ tag }: { tag: TagUsageApi }) => {
                    await tagsDestroy(String(values.currentProjectId), tag.id)
                    lemonToast.success(`Deleted "${tag.name}"`)
                    actions.refreshTags()
                    return (values.tags ?? []).filter((existing) => existing.id !== tag.id)
                },
                mergeTag: async ({ tag, intoId }: { tag: TagUsageApi; intoId: string }) => {
                    const merged = await tagsMergeCreate(String(values.currentProjectId), tag.id, { into_id: intoId })
                    lemonToast.success(`Merged "${tag.name}" into "${merged.name}"`)
                    actions.refreshTags()
                    // A merge folds two rows into one and moves counts, so reload rather than patch.
                    return values.tags
                },
            },
        ],
    })),
    listeners(({ actions }) => ({
        setSearch: async (_, breakpoint) => {
            await breakpoint(300)
            actions.loadTags()
        },
        mergeTagSuccess: () => actions.loadTags(),
    })),
    afterMount(({ actions }) => {
        actions.loadTags()
    }),
])
