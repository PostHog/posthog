/** Matches TAG_USAGE_PAGE_SIZE in posthog/api/tagged_item.py. */
const TAG_PAGE_SIZE = 500

/** Which TaggedItem kind holds support tickets, as the tags usage endpoint keys it. */
const TICKET_KIND = 'ticket'

export function ticketCount(tag: TagUsageApi): number {
    return tag.counts_by_type[TICKET_KIND] ?? 0
}

export function otherObjectCount(tag: TagUsageApi): number {
    return tag.total_count - ticketCount(tag)
}

/** Turn an object kind from the usage endpoint, such as `feature_flag`, into a plural label. */
export function objectKindLabel(kind: string, count: number): string {
    const singular = kind.replace(/_/g, ' ')
    return `${count} ${count === 1 ? singular : `${singular}s`}`
}

