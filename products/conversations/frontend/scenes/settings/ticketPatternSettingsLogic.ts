export const ticketPatternSettingsLogic = kea<ticketPatternSettingsLogicType>([
    path(['products', 'conversations', 'frontend', 'scenes', 'settings', 'ticketPatternSettingsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
        actions: [teamLogic, ['updateCurrentTeam', 'updateCurrentTeamSuccess', 'updateCurrentTeamFailure']],
    })),
    actions({
        updateSettings: (patch: Partial<TicketPatternSettings>) => ({ patch }),
        addOverride: (kind: TicketTopicOverrideKindEnumApi, topic: string) => ({ kind, topic }),
        removeOverride: (id: string) => ({ id }),
    }),
    loaders(() => ({
        overrides: [
            [] as TicketTopicOverrideApi[],
            {
                loadOverrides: async () => {
                    const response = await api.conversationsPatternOverridesList(String(getCurrentTeamId()))
                    return [...response.results]
                },
            },
        ],
    })),
    reducers({
        saving: [
            false,
            {
                updateSettings: () => true,
                updateCurrentTeamSuccess: () => false,
                updateCurrentTeamFailure: () => false,
            },
        ],
        overrides: {
            removeOverride: (state, { id }) => state.filter((o) => o.id !== id),
        },
    }),
    selectors({
        settings: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): TicketPatternSettings => readSettings(currentTeam),
        ],
    }),
    listeners(({ actions, values }) => ({
        updateSettings: ({ patch }) => {
            const next = { ...values.settings, ...patch }
            actions.updateCurrentTeam({
                conversations_settings: {
                    ...(values.currentTeam as TeamType | null)?.conversations_settings,
                    pattern_detection_enabled: next.enabled,
                    pattern_min_requesters: next.minRequesters,
                    pattern_min_tickets: next.minTickets,
                    pattern_window_minutes: next.windowMinutes,
                    pattern_notify_role_id: next.notifyRoleId,
                },
            })
        },
        addOverride: async ({ kind, topic }) => {
            try {
                await api.conversationsPatternOverridesCreate(String(getCurrentTeamId()), { kind, topic })
                actions.loadOverrides()
            } catch (error: any) {
                lemonToast.error(error?.detail ?? "Couldn't add the override. Try again.")
            }
        },
        removeOverride: async ({ id }) => {
            try {
                await api.conversationsPatternOverridesDestroy(String(getCurrentTeamId()), id)
            } catch {
                lemonToast.error("Couldn't remove the override. Try again.")
                actions.loadOverrides()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadOverrides()
    }),
])
