export interface TicketPatternSettings {
    enabled: boolean
    minRequesters: number
    minTickets: number
    windowMinutes: number
    notifyRoleId: string | null
}

const DEFAULTS: TicketPatternSettings = {
    enabled: false,
    minRequesters: 5,
    minTickets: 5,
    windowMinutes: 60,
    notifyRoleId: null,
}

function readSettings(team: TeamPublicType | TeamType | null): TicketPatternSettings {
    const raw = (team as TeamType | null)?.conversations_settings ?? {}
    return {
        enabled: !!raw.pattern_detection_enabled,
        minRequesters: Number(raw.pattern_min_requesters) || DEFAULTS.minRequesters,
        minTickets: Number(raw.pattern_min_tickets) || DEFAULTS.minTickets,
        windowMinutes: Number(raw.pattern_window_minutes) || DEFAULTS.windowMinutes,
        notifyRoleId: typeof raw.pattern_notify_role_id === 'string' ? raw.pattern_notify_role_id : null,
    }
}

