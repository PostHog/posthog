import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { HogQLQueryString } from 'lib/utils/hogql'

import { DataVisualizationNode, DateRange, ProductKey } from '~/queries/schema/schema-general'

import {
    SUPPORT_OVERVIEW_NUMBERS_QUERY,
    SupportOverviewNumbers,
    firstResponseTimeQuery,
    parseSupportOverviewNumbers,
    slaAttainmentQuery,
    ticketsCreatedQuery,
    ticketsResolvedQuery,
} from './supportOverviewQueries'

export const SUPPORT_OVERVIEW_DEFAULT_DATE_FROM = '-30d'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface supportOverviewSceneLogicValues {
    dateFilter: {
        dateFrom: string | null
        dateTo: string | null
    }
    dateRange: DateRange
    firstResponseTimeQuery: DataVisualizationNode
    numbers: SupportOverviewNumbers | null
    numbersFailed: boolean
    numbersLoading: boolean
    slaAttainmentQuery: DataVisualizationNode
    ticketsCreatedQuery: DataVisualizationNode
    ticketsResolvedQuery: DataVisualizationNode
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface supportOverviewSceneLogicActions {
    loadNumbers: () => any
    loadNumbersFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadNumbersSuccess: (
        numbers: SupportOverviewNumbers,
        payload?: any
    ) => {
        numbers: SupportOverviewNumbers
        payload?: any
    }
    setDates: (
        dateFrom: string | null,
        dateTo: string | null
    ) => {
        dateFrom: string | null
        dateTo: string | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface supportOverviewSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        dateRange: (dateFilter: { dateFrom: string | null; dateTo: string | null }) => DateRange
        ticketsCreatedQuery: (dateRange: DateRange) => DataVisualizationNode
        ticketsResolvedQuery: (dateRange: DateRange) => DataVisualizationNode
        firstResponseTimeQuery: (dateRange: DateRange) => DataVisualizationNode
        slaAttainmentQuery: (dateRange: DateRange) => DataVisualizationNode
    }
}

export type supportOverviewSceneLogicType = MakeLogicType<
    supportOverviewSceneLogicValues,
    supportOverviewSceneLogicActions,
    Record<string, any>,
    supportOverviewSceneLogicMeta
>

export const supportOverviewSceneLogic = kea<supportOverviewSceneLogicType>([
    path(['products', 'conversations', 'frontend', 'scenes', 'overview', 'supportOverviewSceneLogic']),
    actions({
        setDates: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
    }),
    loaders({
        numbers: [
            null as SupportOverviewNumbers | null,
            {
                loadNumbers: async (): Promise<SupportOverviewNumbers> => {
                    const response = await api.queryHogQL(SUPPORT_OVERVIEW_NUMBERS_QUERY as HogQLQueryString, {
                        scene: 'SupportOverview',
                        productKey: ProductKey.CONVERSATIONS,
                        name: 'support_overview_numbers',
                    })
                    return parseSupportOverviewNumbers(response.results?.[0])
                },
            },
        ],
    }),
    reducers({
        dateFilter: [
            { dateFrom: SUPPORT_OVERVIEW_DEFAULT_DATE_FROM, dateTo: null } as {
                dateFrom: string | null
                dateTo: string | null
            },
            {
                setDates: (_, { dateFrom, dateTo }) => ({ dateFrom, dateTo }),
            },
        ],
        numbersFailed: [
            false,
            {
                loadNumbers: () => false,
                loadNumbersSuccess: () => false,
                loadNumbersFailure: () => true,
            },
        ],
    }),
    selectors({
        dateRange: [
            (s) => [s.dateFilter],
            (dateFilter: { dateFrom: string | null; dateTo: string | null }): DateRange => ({
                date_from: dateFilter.dateFrom ?? SUPPORT_OVERVIEW_DEFAULT_DATE_FROM,
                date_to: dateFilter.dateTo,
            }),
        ],
        ticketsCreatedQuery: [(s) => [s.dateRange], (dateRange: DateRange) => ticketsCreatedQuery(dateRange)],
        ticketsResolvedQuery: [(s) => [s.dateRange], (dateRange: DateRange) => ticketsResolvedQuery(dateRange)],
        firstResponseTimeQuery: [(s) => [s.dateRange], (dateRange: DateRange) => firstResponseTimeQuery(dateRange)],
        slaAttainmentQuery: [(s) => [s.dateRange], (dateRange: DateRange) => slaAttainmentQuery(dateRange)],
    }),
    listeners({
        setDates: ({ dateFrom, dateTo }) => {
            // pinned: analytics event name and properties, because renaming them breaks dashboards.
            posthog.capture('support overview date range changed', { date_from: dateFrom, date_to: dateTo })
        },
    }),
    afterMount(({ actions }) => {
        actions.loadNumbers()
    }),
])
