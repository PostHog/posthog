export type TicketFilterKey =
    | 'status'
    | 'priority'
    | 'assignee'
    | 'sla'
    | 'channel'
    | 'tags'
    | 'aiTriageResult'
    | 'date'

export const TICKET_FILTER_LABELS: Record<TicketFilterKey, string> = {
    status: 'Status',
    priority: 'Priority',
    assignee: 'Assignee',
    sla: 'SLA',
    channel: 'Channel',
    tags: 'Tags',
    aiTriageResult: 'AI result',
    date: 'Date',
}

const TICKET_FILTER_ORDER: TicketFilterKey[] = [
    'status',
    'priority',
    'assignee',
    'sla',
    'channel',
    'tags',
    'aiTriageResult',
    'date',
]

