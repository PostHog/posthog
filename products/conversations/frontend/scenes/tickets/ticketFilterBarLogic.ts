function offeredFilterKeys(aiEnabled: boolean): TicketFilterKey[] {
    return TICKET_FILTER_ORDER.filter((filterKey) => filterKey !== 'aiTriageResult' || aiEnabled)
}

// The date range is a persisted preference that defaults to the last 7 days, so it is never
// "unset" the way the other filters are. It stays on screen instead of living behind "Filter".
const PINNED_FILTER_KEYS: TicketFilterKey[] = ['date']

// Tracks which filters the person added from the "Filter" menu but has not given a value yet.
// A filter with a value is always shown; one without a value is shown only while it is open.
export const ticketFilterBarLogic: LogicWrapper<ticketFilterBarLogicType> = kea<ticketFilterBarLogicType>([
    props({} as SupportTicketsSceneLogicProps),
    key((props: SupportTicketsSceneLogicProps) => props?.key || 'SupportTicketsScene'),
    path((key) => ['products', 'conversations', 'frontend', 'scenes', 'tickets', 'ticketFilterBarLogic', key]),
    connect((props: SupportTicketsSceneLogicProps) => ({
        values: [supportTicketsSceneLogic(props), ['currentFilters', 'assigneeFilterEntries', 'aiEnabled']],
        actions: [supportTicketsSceneLogic(props), ['applyViewFilters', 'applyUrlFilters']],
    })),
    actions({
        openFilter: (filterKey: TicketFilterKey) => ({ filterKey }),
        closeFilter: (filterKey: TicketFilterKey) => ({ filterKey }),
    }),
    reducers({
        openFilterKeys: [
            [] as TicketFilterKey[],
            {
                openFilter: (state, { filterKey }) => (state.includes(filterKey) ? state : [...state, filterKey]),
                closeFilter: (state, { filterKey }) => state.filter((key) => key !== filterKey),
                applyViewFilters: () => [],
                applyUrlFilters: () => [],
            },
        ],
    }),
    selectors({
        activeFilterKeys: [
            (s) => [s.currentFilters, s.assigneeFilterEntries],
            (currentFilters: TicketViewFilters, assignee: AssigneeFilterEntry[]): TicketFilterKey[] => {
                const active: Record<TicketFilterKey, boolean> = {
                    status: (currentFilters.status?.length ?? 0) > 0,
                    priority: (currentFilters.priority?.length ?? 0) > 0,
                    assignee: assignee.length > 0,
                    sla: !!currentFilters.sla && currentFilters.sla !== 'all',
                    channel: !!currentFilters.channel && currentFilters.channel !== 'all',
                    tags: (currentFilters.tags?.length ?? 0) > 0 || (currentFilters.tagsExclude?.length ?? 0) > 0,
                    aiTriageResult: (currentFilters.aiTriageResult?.length ?? 0) > 0,
                    date: !!currentFilters.dateFrom || !!currentFilters.dateTo,
                }
                return TICKET_FILTER_ORDER.filter((filterKey) => active[filterKey])
            },
        ],
        visibleFilterKeys: [
            (s) => [s.activeFilterKeys, s.openFilterKeys, s.aiEnabled],
            (
                activeFilterKeys: TicketFilterKey[],
                openFilterKeys: TicketFilterKey[],
                aiEnabled: boolean
            ): TicketFilterKey[] =>
                offeredFilterKeys(aiEnabled).filter(
                    (filterKey) =>
                        PINNED_FILTER_KEYS.includes(filterKey) ||
                        activeFilterKeys.includes(filterKey) ||
                        openFilterKeys.includes(filterKey)
                ),
        ],
        // The pinned date range always has a value, so on its own it is not something to clear.
        hasClearableFilters: [
            (s) => [s.activeFilterKeys],
            (activeFilterKeys: TicketFilterKey[]): boolean =>
                activeFilterKeys.some((filterKey) => !PINNED_FILTER_KEYS.includes(filterKey)),
        ],
        addableFilterKeys: [
            (s) => [s.visibleFilterKeys, s.aiEnabled],
            (visibleFilterKeys: TicketFilterKey[], aiEnabled: boolean): TicketFilterKey[] =>
                offeredFilterKeys(aiEnabled).filter(
                    (filterKey) => !PINNED_FILTER_KEYS.includes(filterKey) && !visibleFilterKeys.includes(filterKey)
                ),
        ],
    }),
])
