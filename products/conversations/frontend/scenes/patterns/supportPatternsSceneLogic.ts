import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { getCurrentTeamId } from 'lib/utils/getAppContext'

import { ticketPatternsLogic } from '../../components/TicketPatterns/ticketPatternsLogic'
import * as api from '../../generated/api'
import type { TicketPatternApi } from '../../generated/api.schemas'

export type PatternStatusFilter = 'open' | 'confirmed' | 'dismissed' | 'resolved' | 'all'

const PATTERN_STATUS_FILTERS: PatternStatusFilter[] = ['open', 'confirmed', 'dismissed', 'resolved', 'all']

function toPatternStatusFilter(value: unknown): PatternStatusFilter | null {
    return typeof value === 'string' && (PATTERN_STATUS_FILTERS as string[]).includes(value)
        ? (value as PatternStatusFilter)
        : null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface supportPatternsSceneLogicValues {
    inFlightIds: string[] // ticketPatternsLogic
    patternsEnabled: boolean // ticketPatternsLogic
    patterns: TicketPatternApi[]
    patternsLoading: boolean
    statusFilter: PatternStatusFilter
    visiblePatterns: TicketPatternApi[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface supportPatternsSceneLogicActions {
    decisionSucceeded: (pattern: TicketPatternApi) => {
        pattern: TicketPatternApi
    } // ticketPatternsLogic
    loadPatterns: () => {
        value: true
    }
    loadPatternsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadPatternsSuccess: (
        patterns: TicketPatternApi[],
        payload?: {
            value: true
        }
    ) => {
        patterns: TicketPatternApi[]
        payload?: {
            value: true
        }
    }
    setStatusFilter: (statusFilter: PatternStatusFilter) => {
        statusFilter: PatternStatusFilter
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface supportPatternsSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        visiblePatterns: (
            patterns: TicketPatternApi[],
            statusFilter: PatternStatusFilter,
            inFlightIds: string[]
        ) => TicketPatternApi[]
    }
}

export type supportPatternsSceneLogicType = MakeLogicType<
    supportPatternsSceneLogicValues,
    supportPatternsSceneLogicActions,
    Record<string, any>,
    supportPatternsSceneLogicMeta
>

export const supportPatternsSceneLogic = kea<supportPatternsSceneLogicType>([
    path(['products', 'conversations', 'frontend', 'scenes', 'patterns', 'supportPatternsSceneLogic']),
    connect(() => ({
        actions: [ticketPatternsLogic, ['decisionSucceeded']],
        values: [ticketPatternsLogic, ['inFlightIds', 'patternsEnabled']],
    })),
    actions({
        // Declared parameterless so callers dispatch it without a payload: the loader below takes
        // the breakpoint as its second argument.
        loadPatterns: true,
        setStatusFilter: (statusFilter: PatternStatusFilter) => ({ statusFilter }),
    }),
    loaders(({ values }) => ({
        patterns: [
            [] as TicketPatternApi[],
            {
                loadPatterns: async (_, breakpoint) => {
                    const status = values.statusFilter === 'all' ? undefined : values.statusFilter
                    const response = await api.conversationsPatternsList(String(getCurrentTeamId()), { status })
                    // Drop a response that was superseded while in flight, so a slow reply for the
                    // filter the person left cannot overwrite the newer one.
                    breakpoint()
                    return [...response.results]
                },
            },
        ],
    })),
    reducers({
        statusFilter: ['open' as PatternStatusFilter, { setStatusFilter: (_, { statusFilter }) => statusFilter }],
        patterns: {
            // The banner and this list share the decision actions, so a confirm made anywhere updates the row here.
            decisionSucceeded: (state, { pattern }) => state.map((p) => (p.id === pattern.id ? pattern : p)),
        },
    }),
    selectors({
        // A decision updates the row in place, so a row that no longer matches the active filter has to
        // drop out of the list. A row with a decision in flight drops out too, and comes back if it fails.
        visiblePatterns: [
            (s) => [s.patterns, s.statusFilter, s.inFlightIds],
            (
                patterns: TicketPatternApi[],
                statusFilter: PatternStatusFilter,
                inFlightIds: string[]
            ): TicketPatternApi[] =>
                statusFilter === 'all'
                    ? patterns
                    : patterns.filter((p) => p.status === statusFilter && !inFlightIds.includes(p.id)),
        ],
    }),
    listeners(({ actions }) => ({
        setStatusFilter: () => actions.loadPatterns(),
    })),
    urlToAction(({ actions, values }) => ({
        // The panel on a ticket links here with the pattern's own status, so a confirmed pattern lands
        // on a filter that holds it instead of on the default "Needs review".
        '/support/patterns': (_, searchParams) => {
            const status = toPatternStatusFilter(searchParams.status)
            if (values.patternsEnabled && status && status !== values.statusFilter) {
                actions.setStatusFilter(status)
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setStatusFilter: () => [
            router.values.location.pathname,
            { ...router.values.searchParams, status: values.statusFilter },
            router.values.hashParams,
            { replace: true },
        ],
    })),
    afterMount(({ actions, values }) => {
        // A status in the URL already started a load through setStatusFilter.
        if (values.patternsEnabled && !values.patternsLoading) {
            actions.loadPatterns()
        }
    }),
])
