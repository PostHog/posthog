import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'

import { UI_CONFIGURATION_VERSION, uiCustomizationLogic } from '~/layout/uiCustomizationLogic'
import { HogQLQuery, NodeKind, ProductKey, UserUIConfiguration } from '~/queries/schema/schema-general'

// pinned: analytics event name. Renaming it breaks insights built on it.
const QUERY_RUN_EVENT = 'support ticket sql query run'

export const DEFAULT_TICKET_SQL_QUERY = `SELECT timestamp, event, properties.$current_url AS url
FROM events
WHERE person_id = {person_id}
    AND timestamp > now() - INTERVAL 7 DAY
ORDER BY timestamp DESC
LIMIT 20`

export interface TicketSqlEditorLogicProps {
    personId: string
    distinctId: string
}

export type TicketSqlPlaceholders = {
    person_id: string
    distinct_id: string
}

export interface TicketSqlResult {
    columns: string[]
    rows: unknown[][]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketSqlEditorLogicValues {
    uiConfiguration: UserUIConfiguration | null // uiCustomizationLogic
    editorQuery: string
    placeholders: TicketSqlPlaceholders
    queryError: string | null
    queryInput: string | null
    result: TicketSqlResult | null
    resultLoading: boolean
    savedQuery: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketSqlEditorLogicActions {
    updateUiConfiguration: (
        configuration: UserUIConfiguration,
        successCallback?: (() => void) | undefined,
        failureCallback?: (() => void) | undefined
    ) => {
        configuration: UserUIConfiguration
        failureCallback: (() => void) | undefined
        successCallback: (() => void) | undefined
    } // uiCustomizationLogic
    resetQuery: () => {
        value: true
    }
    runQuery: (query: string) => string
    runQueryFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    runQuerySuccess: (
        result: {
            columns: string[]
            rows: any[]
        },
        payload?: string
    ) => {
        result: {
            columns: string[]
            rows: any[]
        }
        payload?: string
    }
    setQueryInput: (query: string) => {
        query: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketSqlEditorLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        savedQuery: (uiConfiguration: UserUIConfiguration | null) => string
        editorQuery: (queryInput: string | null, savedQuery: string) => string
        placeholders: (personId: string, distinctId: string) => TicketSqlPlaceholders
    }
}

export type ticketSqlEditorLogicType = MakeLogicType<
    ticketSqlEditorLogicValues,
    ticketSqlEditorLogicActions,
    TicketSqlEditorLogicProps,
    ticketSqlEditorLogicMeta
>

export const ticketSqlEditorLogic = kea<ticketSqlEditorLogicType>([
    props({} as TicketSqlEditorLogicProps),
    key((props) => props.personId),
    path((key) => [
        'products',
        'conversations',
        'frontend',
        'components',
        'TicketSqlEditorPanel',
        'ticketSqlEditorLogic',
        key,
    ]),
    connect(() => ({
        values: [uiCustomizationLogic, ['uiConfiguration']],
        actions: [uiCustomizationLogic, ['updateUiConfiguration']],
    })),
    actions({
        setQueryInput: (query: string) => ({ query }),
        resetQuery: true,
    }),
    loaders(({ values }) => ({
        result: [
            null as TicketSqlResult | null,
            {
                runQuery: async (query: string, breakpoint) => {
                    const response = await api.query<HogQLQuery>({
                        kind: NodeKind.HogQLQuery,
                        query,
                        values: values.placeholders,
                        tags: { productKey: ProductKey.CONVERSATIONS },
                    })
                    breakpoint()
                    return { columns: (response.columns ?? []).map(String), rows: response.results ?? [] }
                },
            },
        ],
    })),
    reducers({
        // null until the user types, so the editor follows the saved query until then.
        queryInput: [
            null as string | null,
            {
                setQueryInput: (_, { query }) => query,
                resetQuery: () => DEFAULT_TICKET_SQL_QUERY,
            },
        ],
        queryError: [
            null as string | null,
            {
                runQuery: () => null,
                runQueryFailure: (_, { error, errorObject }) => errorObject?.detail || error,
            },
        ],
    }),
    selectors({
        savedQuery: [
            (s) => [s.uiConfiguration],
            (uiConfiguration: UserUIConfiguration | null): string =>
                uiConfiguration?.ticket_sidebar_sql_query || DEFAULT_TICKET_SQL_QUERY,
        ],
        editorQuery: [
            (s) => [s.queryInput, s.savedQuery],
            (queryInput: string | null, savedQuery: string): string => queryInput ?? savedQuery,
        ],
        placeholders: [
            (_, p) => [p.personId, p.distinctId],
            (personId: string, distinctId: string): TicketSqlPlaceholders => ({
                person_id: personId,
                distinct_id: distinctId,
            }),
        ],
    }),
    listeners(({ actions, values }) => ({
        runQuery: (query) => {
            const { editorQuery, savedQuery, uiConfiguration } = values
            posthog.capture(QUERY_RUN_EVENT, {
                is_default_query: editorQuery === DEFAULT_TICKET_SQL_QUERY,
                ran_selection: query !== editorQuery,
            })
            if (editorQuery === savedQuery) {
                return
            }
            // The server replaces ui_configuration wholesale, so every other key is carried over.
            // Saving the default stores nothing, so the user keeps getting later changes to the default query.
            actions.updateUiConfiguration({
                version: UI_CONFIGURATION_VERSION,
                ...uiConfiguration,
                ticket_sidebar_sql_query: editorQuery === DEFAULT_TICKET_SQL_QUERY ? undefined : editorQuery,
            })
        },
    })),
])
