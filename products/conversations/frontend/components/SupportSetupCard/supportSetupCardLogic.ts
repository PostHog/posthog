export const supportSetupCardLogic = kea<supportSetupCardLogicType>([
    path(['products', 'conversations', 'frontend', 'components', 'SupportSetupCard', 'supportSetupCardLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentProjectId']],
        actions: [
            teamLogic,
            ['updateCurrentTeam', 'updateCurrentTeamSuccess', 'updateCurrentTeamFailure'],
            productSetupStatusLogic({ productKey: ProductKey.CONVERSATIONS }),
            ['reportSetupInteraction'],
        ],
    })),
    actions({
        pickChannel: (channel: SupportSetupChannel, mode: ProductEmptyStateMode, preview: boolean) => ({
            channel,
            mode,
            preview,
        }),
        pickImport: (source: SupportSetupImport, mode: ProductEmptyStateMode, preview: boolean) => ({
            source,
            mode,
            preview,
        }),
        openChannelSettings: (channel: SupportSetupChannel) => ({ channel }),
        openImportSettings: (source: SupportSetupImport) => ({ source }),
        widgetTurnedOn: true,
        cancelPending: true,
        setTestMessage: (message: string) => ({ message }),
    }),
    loaders(({ values }) => ({
        testTicket: [
            null as ComposeTicketResponseApi | null,
            {
                sendTestTicket: async () =>
                    await conversationsTicketsSendTestCreate(String(values.currentProjectId), {
                        message: values.testMessage.trim() || DEFAULT_TEST_MESSAGE,
                    }),
            },
        ],
    })),
    reducers({
        pendingChannel: [
            null as SupportSetupChannel | null,
            {
                pickChannel: (_, { channel }) => channel,
                pickImport: () => null,
                openChannelSettings: () => null,
                widgetTurnedOn: () => null,
                cancelPending: () => null,
                updateCurrentTeamFailure: () => null,
            },
        ],
        pendingImport: [
            null as SupportSetupImport | null,
            {
                pickImport: (_, { source }) => source,
                pickChannel: () => null,
                openImportSettings: () => null,
                cancelPending: () => null,
                updateCurrentTeamFailure: () => null,
            },
        ],
        testMessage: [
            DEFAULT_TEST_MESSAGE as string,
            {
                setTestMessage: (_, { message }) => message,
            },
        ],
    }),
    selectors({
        pendingReason: [
            (s) => [s.pendingChannel, s.pendingImport, s.testTicketLoading],
            (
                pendingChannel: SupportSetupChannel | null,
                pendingImport: SupportSetupImport | null,
                testTicketLoading: boolean
            ): string | null => {
                if (pendingChannel || pendingImport) {
                    return 'Turning Support on…'
                }
                return testTicketLoading ? 'Sending the test ticket…' : null
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        pickChannel: ({ channel, mode, preview }) => {
            actions.reportSetupInteraction('channel picked', mode, null, preview)
            if (!preview) {
                // pinned: analytics event name. Renaming it breaks insights built on it.
                posthog.capture('support setup channel picked', { channel, mode })
            }
            const team = values.currentTeam
            const supportEnabled = !!team?.conversations_enabled
            const widgetEnabled = !!team?.conversations_settings?.widget_enabled
            // A preview renders on a project that has tickets, so it must not change settings.
            if (preview || (supportEnabled && (channel !== 'widget' || widgetEnabled))) {
                actions.openChannelSettings(channel)
                return
            }
            if (channel === 'widget') {
                // The widget has no required configuration, so one request turns on Support and the widget together.
                actions.updateCurrentTeam({
                    ...(supportEnabled ? {} : { conversations_enabled: true }),
                    conversations_settings: { ...team?.conversations_settings, widget_enabled: true },
                })
                return
            }
            // The channel tabs in Support settings only render once Support is on.
            actions.updateCurrentTeam({ conversations_enabled: true })
        },
        pickImport: ({ source, mode, preview }) => {
            actions.reportSetupInteraction('import picked', mode, null, preview)
            if (!preview) {
                // pinned: analytics event name. Renaming it breaks insights built on it.
                posthog.capture('support setup import picked', { source, mode })
            }
            if (preview || values.currentTeam?.conversations_enabled) {
                actions.openImportSettings(source)
                return
            }
            // The import tabs in Support settings only render once Support is on.
            actions.updateCurrentTeam({ conversations_enabled: true })
        },
        updateCurrentTeamSuccess: ({ currentTeam, payload }) => {
            const channel = values.pendingChannel
            const source = values.pendingImport
            if (!channel && !source) {
                return
            }
            // teamLogic drops the enable request's result when a newer team update starts, so check the team.
            if (!currentTeam?.conversations_enabled) {
                actions.cancelPending()
                return
            }
            if (payload?.conversations_enabled) {
                // pinned: analytics event name and `source` value. Renaming them breaks insights built on them.
                posthog.capture('support activation completed', {
                    source: 'support_empty_state',
                    channel: channel ?? undefined,
                    import_source: source ?? undefined,
                })
            }
            if (source) {
                actions.openImportSettings(source)
            } else if (channel !== 'widget') {
                actions.openChannelSettings(channel as SupportSetupChannel)
            } else if (currentTeam.conversations_settings?.widget_enabled) {
                actions.widgetTurnedOn()
            } else {
                actions.cancelPending()
            }
        },
        widgetTurnedOn: () => {
            // pinned: analytics event name. Renaming it breaks insights built on it.
            posthog.capture('support setup widget turned on')
        },
        openChannelSettings: ({ channel }) => {
            router.actions.push(urls.supportSettings(), {}, { channel })
        },
        openImportSettings: ({ source }) => {
            router.actions.push(
                urls.supportSettings(),
                {},
                { selectedSetting: 'conversations-imports', import: source }
            )
        },
        sendTestTicketSuccess: ({ testTicket }) => {
            if (!testTicket) {
                return
            }
            // pinned: analytics event name. Renaming it breaks insights built on it.
            posthog.capture('support setup test ticket sent', {
                custom_message: values.testMessage.trim() !== DEFAULT_TEST_MESSAGE,
            })
            router.actions.push(urls.supportTicketDetail(testTicket.ticket_number))
        },
        sendTestTicketFailure: () => {
            lemonToast.error('Could not send the test ticket. Try again, and contact support if it keeps failing.')
        },
    })),
])
