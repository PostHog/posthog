import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { productSetupStatusLogic } from 'lib/components/ProductEmptyState/productSetupStatusLogic'
import type { ProductEmptyStateMode } from 'lib/components/ProductEmptyState/types'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { ProductKey } from '~/queries/schema/schema-general'
import type { TeamPublicType, TeamType } from '~/types'

// pinned: these are the `channel` hash values the channel tabs in Support settings read.
export type SupportSetupChannel = 'widget' | 'email' | 'slack' | 'teams' | 'api'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface supportSetupCardLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    pendingChannel: SupportSetupChannel | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface supportSetupCardLogicActions {
    reportSetupInteraction: (
        action: string,
        mode: ProductEmptyStateMode,
        route?: null | import('lib/components/ProductEmptyState/productSetupStatusLogic').ProductSetupRoute | undefined,
        preview?: boolean | undefined,
        wizardSession?:
            | {
                  phase: string
                  session_id: string
              }
            | undefined
    ) => {
        action: string
        mode: ProductEmptyStateMode
        preview: boolean
        route: null | import('lib/components/ProductEmptyState/productSetupStatusLogic').ProductSetupRoute
        wizardSession:
            | {
                  phase: string
                  session_id: string
              }
            | undefined
    } // productSetupStatusLogic
    updateCurrentTeam: (payload: Partial<TeamType>) => Partial<TeamType> // teamLogic
    updateCurrentTeamFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    } // teamLogic
    updateCurrentTeamSuccess: (
        currentTeam: TeamPublicType | TeamType,
        payload?: Partial<TeamType> | undefined
    ) => {
        currentTeam: TeamPublicType | TeamType
        payload?: Partial<TeamType>
    } // teamLogic
    cancelPendingChannel: () => {
        value: true
    }
    openChannelSettings: (channel: SupportSetupChannel) => {
        channel: SupportSetupChannel
    }
    pickChannel: (
        channel: SupportSetupChannel,
        mode: ProductEmptyStateMode,
        preview: boolean
    ) => {
        channel: SupportSetupChannel
        mode: ProductEmptyStateMode
        preview: boolean
    }
}

export type supportSetupCardLogicType = MakeLogicType<supportSetupCardLogicValues, supportSetupCardLogicActions>

export const supportSetupCardLogic = kea<supportSetupCardLogicType>([
    path(['products', 'conversations', 'frontend', 'components', 'SupportSetupCard', 'supportSetupCardLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
        actions: [
            teamLogic,
            ['updateCurrentTeam', 'updateCurrentTeamSuccess', 'updateCurrentTeamFailure'],
            productSetupStatusLogic({ productKey: ProductKey.CONVERSATIONS }),
            ['reportSetupInteraction'],
        ],
    })),
    actions({
        pickChannel: (channel: SupportSetupChannel, mode: ProductEmptyStateMode, preview: boolean) => ({
            channel,
            mode,
            preview,
        }),
        openChannelSettings: (channel: SupportSetupChannel) => ({ channel }),
        cancelPendingChannel: true,
    }),
    reducers({
        pendingChannel: [
            null as SupportSetupChannel | null,
            {
                pickChannel: (_, { channel }) => channel,
                openChannelSettings: () => null,
                cancelPendingChannel: () => null,
                updateCurrentTeamFailure: () => null,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        pickChannel: ({ channel, mode, preview }) => {
            actions.reportSetupInteraction('channel picked', mode, null, preview)
            if (!preview) {
                // pinned: analytics event name. Renaming it breaks insights built on it.
                posthog.capture('support setup channel picked', { channel, mode })
            }
            // A preview renders on a project that has tickets, so it must not change settings.
            if (preview || values.currentTeam?.conversations_enabled) {
                actions.openChannelSettings(channel)
                return
            }
            // The channel tabs in Support settings only render once Support is on.
            actions.updateCurrentTeam({ conversations_enabled: true })
        },
        updateCurrentTeamSuccess: ({ currentTeam }) => {
            const channel = values.pendingChannel
            if (!channel) {
                return
            }
            // teamLogic drops the enable request's result when a newer team update starts, so check the team.
            if (!currentTeam?.conversations_enabled) {
                actions.cancelPendingChannel()
                return
            }
            // pinned: analytics event name and `source` value. Renaming them breaks insights built on them.
            posthog.capture('support activation completed', { source: 'support_empty_state', channel })
            actions.openChannelSettings(channel)
        },
        openChannelSettings: ({ channel }) => {
            router.actions.push(urls.supportSettings(), {}, { channel })
        },
    })),
])
