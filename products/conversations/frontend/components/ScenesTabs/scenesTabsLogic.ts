import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router, urlToAction } from 'kea-router'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import type { FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import type { TeamPublicType, TeamType } from '~/types'

import type { SceneTabKey } from '../../types'

export type SceneTabConfig = {
    key: SceneTabKey
    label: string
    href: string
    /** Release stage shown as a tag after the label, e.g. "Alpha". */
    stage?: string
}

export const SCENE_TABS: SceneTabConfig[] = [
    {
        key: 'tickets',
        label: 'Tickets',
        href: urls.supportTickets(),
    },
    {
        key: 'patterns',
        label: 'Patterns',
        href: urls.supportPatterns(),
        stage: 'Alpha',
    },
    {
        key: 'settings',
        label: 'Settings',
        href: urls.supportSettings(),
    },
]

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scenesTabsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    activeTab: SceneTabKey
    tabs: SceneTabConfig[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scenesTabsLogicActions {
    setActiveTab: (tab: SceneTabKey) => {
        tab: SceneTabKey
    }
    setTab: (tab: SceneTabKey) => {
        tab: SceneTabKey
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface scenesTabsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        tabs: (featureFlags: FeatureFlagsSet, currentTeam: TeamPublicType | TeamType | null) => SceneTabConfig[]
    }
}

export type scenesTabsLogicType = MakeLogicType<
    scenesTabsLogicValues,
    scenesTabsLogicActions,
    Record<string, any>,
    scenesTabsLogicMeta
>

export const scenesTabsLogic = kea<scenesTabsLogicType>([
    path(['products', 'conversations', 'frontend', 'components', 'ScenesTabs', 'scenesTabsLogic']),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags'], teamLogic, ['currentTeam']] })),
    actions({
        setTab: (tab: SceneTabKey) => ({ tab }),
        setActiveTab: (tab: SceneTabKey) => ({ tab }),
    }),
    reducers({
        activeTab: [
            'tickets' as SceneTabKey,
            {
                setActiveTab: (_state: SceneTabKey, { tab }: { tab: SceneTabKey }) => tab,
            },
        ],
    }),
    selectors({
        // The Patterns tab shows only once detection is on for the project. With detection off nothing
        // opens, so the tab would lead to a page that is always empty. Settings keeps a link to it.
        tabs: [
            (s) => [s.featureFlags, s.currentTeam],
            (
                featureFlags: Record<string, boolean | string | undefined>,
                currentTeam: TeamPublicType | TeamType | null
            ): SceneTabConfig[] => {
                const detectionOn = !!(currentTeam as TeamType | null)?.conversations_settings
                    ?.pattern_detection_enabled
                return SCENE_TABS.filter(
                    (tab) =>
                        tab.key !== 'patterns' ||
                        (!!featureFlags[FEATURE_FLAGS.PRODUCT_SUPPORT_TICKET_PATTERNS] && detectionOn)
                )
            },
        ],
    }),
    listeners({
        setTab: ({ tab }: { tab: SceneTabKey }) => {
            const target = SCENE_TABS.find((sceneTab) => sceneTab.key === tab)?.href
            if (target) {
                router.actions.push(target)
            }
        },
    }),
    urlToAction(({ actions }) => {
        return {
            '/support/tickets': () => actions.setActiveTab('tickets'),
            '/support/tickets/:ticketId': () => actions.setActiveTab('tickets'),
            '/support/patterns': () => actions.setActiveTab('patterns'),
            '/support/settings': () => actions.setActiveTab('settings'),
        }
    }),
])
