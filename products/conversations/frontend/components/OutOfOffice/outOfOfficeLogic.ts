export type outOfOfficeLogicType = MakeLogicType<
    outOfOfficeLogicValues,
    outOfOfficeLogicActions,
    Record<string, any>,
    outOfOfficeLogicMeta
>

export const outOfOfficeLogic = kea<outOfOfficeLogicType>([
    path(['products', 'conversations', 'frontend', 'components', 'OutOfOffice', 'outOfOfficeLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], userLogic, ['user'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        setAway: (away: boolean) => ({ away }),
        setAwaySaving: (saving: boolean) => ({ saving }),
    }),
    loaders(({ values }) => ({
        entries: [
            [] as AgentOutOfOfficeApi[],
            {
                loadEntries: async () => {
                    if (!values.currentTeamId || !values.enabled) {
                        return []
                    }
                    const collected: AgentOutOfOfficeApi[] = []
                    while (collected.length < 1000) {
                        const page = await conversationsOutOfOfficeList(String(values.currentTeamId), {
                            limit: 100,
                            offset: collected.length,
                        })
                        collected.push(...page.results)
                        if (!page.next || page.results.length === 0) {
                            break
                        }
                    }
                    return collected
                },
            },
        ],
    })),
    reducers({
        awaySaving: [false, { setAwaySaving: (_, { saving }) => saving }],
    }),
    selectors({
        enabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.PRODUCT_SUPPORT_OUT_OF_OFFICE],
        ],
        myEntry: [
            (s) => [s.entries, s.user],
            (entries: AgentOutOfOfficeApi[], user: UserType | null): AgentOutOfOfficeApi | null =>
                entries.find((entry) => entry.user.uuid === user?.uuid) ?? null,
        ],
        awayUserIds: [
            (s) => [s.entries],
            (entries: AgentOutOfOfficeApi[]): Set<number> => new Set(entries.map((entry) => entry.user.id)),
        ],
    }),
    listeners(({ actions, values }) => ({
        setAway: async ({ away }) => {
            if (!values.currentTeamId || values.awaySaving) {
                return
            }
            actions.setAwaySaving(true)
            try {
                if (away) {
                    await conversationsOutOfOfficeMeCreate(String(values.currentTeamId))
                } else {
                    await conversationsOutOfOfficeMeDestroy(String(values.currentTeamId))
                }
                actions.loadEntries()
            } catch {
                lemonToast.error(away ? "Couldn't set you out of office." : "Couldn't clear your out of office.")
            } finally {
                actions.setAwaySaving(false)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadEntries()
    }),
])
