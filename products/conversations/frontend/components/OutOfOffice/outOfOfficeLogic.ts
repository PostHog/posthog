import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { teamLogic } from 'scenes/teamLogic'
import { userLogic } from 'scenes/userLogic'

import { UserType } from '~/types'

import {
    conversationsOutOfOfficeList,
    conversationsOutOfOfficeMeCreate,
    conversationsOutOfOfficeMeDestroy,
} from 'products/conversations/frontend/generated/api'
import type { AgentOutOfOfficeApi } from 'products/conversations/frontend/generated/api.schemas'

