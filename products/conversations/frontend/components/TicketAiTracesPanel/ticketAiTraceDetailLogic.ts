import { MakeLogicType, afterMount, kea, key, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import { dayjs } from 'lib/dayjs'

import { LLMTrace, LLMTraceEvent, NodeKind, ProductKey, TraceQuery } from '~/queries/schema/schema-general'

export interface TicketAiTraceDetailLogicProps {
    traceId: string
    /** The timestamp of the trace's first event. */
    createdAt: string
}

const CONVERSATION_EVENTS = ['$ai_generation', '$ai_embedding']
const STATE_EVENTS = ['$ai_trace', '$ai_span']

/** The LLM calls of a trace, or, for a trace without any, the steps that recorded an input or output state. */
export function traceEventsToShow(trace: LLMTrace | null): LLMTraceEvent[] {
    if (!trace) {
        return []
    }
    const calls = trace.events.filter((event) => CONVERSATION_EVENTS.includes(event.event))
    if (calls.length > 0) {
        return calls
    }
    return trace.events.filter(
        (event) =>
            STATE_EVENTS.includes(event.event) &&
            (event.properties.$ai_input_state !== undefined || event.properties.$ai_output_state !== undefined)
    )
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketAiTraceDetailLogicValues {
    eventsToShow: LLMTraceEvent[]
    traceDetail: LLMTrace | null
    traceDetailLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketAiTraceDetailLogicActions {
    loadTraceDetail: () => any
    loadTraceDetailFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTraceDetailSuccess: (
        traceDetail: LLMTrace | null,
        payload?: any
    ) => {
        traceDetail: LLMTrace | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketAiTraceDetailLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        eventsToShow: (traceDetail: LLMTrace | null) => LLMTraceEvent[]
    }
}

export type ticketAiTraceDetailLogicType = MakeLogicType<
    ticketAiTraceDetailLogicValues,
    ticketAiTraceDetailLogicActions,
    TicketAiTraceDetailLogicProps,
    ticketAiTraceDetailLogicMeta
>

export const ticketAiTraceDetailLogic = kea<ticketAiTraceDetailLogicType>([
    props({} as TicketAiTraceDetailLogicProps),
    key((props) => props.traceId),
    path((key) => [
        'products',
        'conversations',
        'frontend',
        'components',
        'TicketAiTracesPanel',
        'ticketAiTraceDetailLogic',
        key,
    ]),
    loaders(({ props }) => ({
        traceDetail: [
            null as LLMTrace | null,
            {
                loadTraceDetail: async (): Promise<LLMTrace | null> => {
                    const response = await api.query<TraceQuery>({
                        kind: NodeKind.TraceQuery,
                        traceId: props.traceId,
                        // Bounds the scan around the trace. The end is generous because an agent run can last a long time.
                        dateRange: {
                            date_from: dayjs(props.createdAt).subtract(1, 'minute').toISOString(),
                            date_to: dayjs(props.createdAt).add(1, 'day').toISOString(),
                        },
                        tags: { productKey: ProductKey.CONVERSATIONS },
                    })
                    return response.results[0] ?? null
                },
            },
        ],
    })),
    selectors({
        eventsToShow: [
            (s) => [s.traceDetail],
            (traceDetail: LLMTrace | null): LLMTraceEvent[] => traceEventsToShow(traceDetail),
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadTraceDetail()
    }),
])
