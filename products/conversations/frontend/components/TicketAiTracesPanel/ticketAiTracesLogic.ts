import { MakeLogicType, afterMount, kea, key, listeners, path, props } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'

import { LLMTrace, NodeKind, ProductKey, TracesQuery } from '~/queries/schema/schema-general'

// pinned: analytics event name. Renaming it breaks insights built on it.
const TRACES_LOADED_EVENT = 'support ticket ai traces loaded'

export const TICKET_AI_TRACES_LIMIT = 5
export const TICKET_AI_TRACES_DATE_FROM = '-30d'

export interface TicketAiTracesLogicProps {
    personId: string
}

export interface TicketAiTracesResult {
    traces: LLMTrace[]
    hasMore: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketAiTracesLogicValues {
    result: TicketAiTracesResult | null
    resultLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketAiTracesLogicActions {
    loadResult: () => any
    loadResultFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadResultSuccess: (
        result: TicketAiTracesResult | null,
        payload?: any
    ) => {
        result: TicketAiTracesResult | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketAiTracesLogicMeta {
    key: string
}

export type ticketAiTracesLogicType = MakeLogicType<
    ticketAiTracesLogicValues,
    ticketAiTracesLogicActions,
    TicketAiTracesLogicProps,
    ticketAiTracesLogicMeta
>

export const ticketAiTracesLogic = kea<ticketAiTracesLogicType>([
    props({} as TicketAiTracesLogicProps),
    key((props) => props.personId),
    path((key) => [
        'products',
        'conversations',
        'frontend',
        'components',
        'TicketAiTracesPanel',
        'ticketAiTracesLogic',
        key,
    ]),
    loaders(({ props }) => ({
        result: [
            null as TicketAiTracesResult | null,
            {
                loadResult: async () => {
                    const response = await api.query<TracesQuery>({
                        kind: NodeKind.TracesQuery,
                        personId: props.personId,
                        limit: TICKET_AI_TRACES_LIMIT,
                        dateRange: { date_from: TICKET_AI_TRACES_DATE_FROM },
                        // Support traces come from staff impersonating the customer, not from the customer.
                        filterSupportTraces: true,
                        tags: { productKey: ProductKey.CONVERSATIONS },
                    })
                    return { traces: response.results, hasMore: !!response.hasMore }
                },
            },
        ],
    })),
    listeners({
        loadResultSuccess: ({ result }) => {
            if (result) {
                posthog.capture(TRACES_LOADED_EVENT, { trace_count: result.traces.length, has_more: result.hasMore })
            }
        },
    }),
    afterMount(({ actions }) => {
        actions.loadResult()
    }),
])
