export type ticketPatternsLogicType = MakeLogicType<
    ticketPatternsLogicValues,
    ticketPatternsLogicActions,
    Record<string, any>,
    ticketPatternsLogicMeta
>

export const ticketPatternsLogic = kea<ticketPatternsLogicType>([
    path(['products', 'conversations', 'frontend', 'components', 'TicketPatterns', 'ticketPatternsLogic']),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags']] })),
    actions({
        confirmPattern: (id: string, body?: ConfirmPatternApi) => ({ id, body }),
        dismissPattern: (id: string, reason?: string) => ({ id, reason }),
        restorePattern: (pattern: TicketPatternApi) => ({ pattern }),
        decisionSucceeded: (pattern: TicketPatternApi) => ({ pattern }),
        decisionFailed: (id: string) => ({ id }),
        hideBanner: (id: string) => ({ id }),
    }),
    loaders(() => ({
        openPatterns: [
            [] as TicketPatternApi[],
            {
                loadOpenPatterns: async () => {
                    const response = await api.conversationsPatternsList(String(getCurrentTeamId()), {
                        status: 'open',
                    })
                    return [...response.results]
                },
            },
        ],
    })),
    reducers({
        openPatterns: {
            // Optimistic: drop the row as soon as the person decides, put it back if the request fails.
            confirmPattern: (state, { id }) => state.filter((p) => p.id !== id),
            dismissPattern: (state, { id }) => state.filter((p) => p.id !== id),
            restorePattern: (state, { pattern }) =>
                state.some((p) => p.id === pattern.id) ? state : [pattern, ...state],
        },
        dismissedBannerIds: [
            [] as string[],
            { persist: true },
            {
                hideBanner: (state, { id }) => (state.includes(id) ? state : [...state, id]),
            },
        ],
        inFlightIds: [
            [] as string[],
            {
                confirmPattern: (state, { id }) => [...state, id],
                dismissPattern: (state, { id }) => [...state, id],
                decisionSucceeded: (state, { pattern }) => state.filter((x) => x !== pattern.id),
                decisionFailed: (state, { id }) => state.filter((x) => x !== id),
            },
        ],
    }),
    selectors({
        patternsEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: Record<string, boolean | string | undefined>): boolean =>
                !!featureFlags[FEATURE_FLAGS.PRODUCT_SUPPORT_TICKET_PATTERNS],
        ],
        bannerPatterns: [
            (s) => [s.openPatterns, s.dismissedBannerIds],
            (openPatterns: TicketPatternApi[], dismissedBannerIds: string[]): TicketPatternApi[] =>
                openPatterns.filter((p) => !dismissedBannerIds.includes(p.id)),
        ],
    }),
    listeners(({ actions, cache }) => {
        // A 400 on `status` is the server refusing a second transition: either someone else decided
        // this pattern first, or a request of our own landed and lost its response. Restoring the row
        // would put a stale open pattern back in front of everyone, so read the decided pattern.
        const settleFailure = async (id: string, error: unknown, retryMessage: string): Promise<void> => {
            if (error instanceof ApiError && error.status === 400 && error.attr === 'status') {
                try {
                    actions.decisionSucceeded(await api.conversationsPatternsRetrieve(String(getCurrentTeamId()), id))
                } catch {
                    actions.decisionFailed(id)
                }
                lemonToast.info('This pattern was already reviewed. The list now shows the decision.')
                return
            }
            const previous = (cache.lastLoaded as TicketPatternApi[] | undefined)?.find((p) => p.id === id)
            if (previous) {
                actions.restorePattern(previous)
            }
            actions.decisionFailed(id)
            lemonToast.error(retryMessage)
        }

        return {
            loadOpenPatternsSuccess: ({ openPatterns }) => {
                // Reducers run before listeners, so by the time a decision listener fires the row is already gone from
                // state. Keep the last loaded list to look the row up for a rollback.
                cache.lastLoaded = openPatterns
            },
            confirmPattern: async ({ id, body }) => {
                try {
                    const pattern = await api.conversationsPatternsConfirmCreate(String(getCurrentTeamId()), id, body)
                    actions.decisionSucceeded(pattern)
                } catch (error) {
                    await settleFailure(id, error, "Couldn't confirm the pattern. Try again.")
                }
            },
            dismissPattern: async ({ id, reason }) => {
                try {
                    const pattern = await api.conversationsPatternsDismissCreate(String(getCurrentTeamId()), id, {
                        reason,
                    })
                    actions.decisionSucceeded(pattern)
                } catch (error) {
                    await settleFailure(id, error, "Couldn't dismiss the pattern. Try again.")
                }
            },
        }
    }),
])
