export const ticketSpikeBannerLogic = kea<ticketSpikeBannerLogicType>([
    path(['products', 'conversations', 'frontend', 'components', 'TicketSpikeBanner', 'ticketSpikeBannerLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentTeamId'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        dismissSpike: (key: string) => ({ key }),
        dismissSpikeFailure: (key: string) => ({ key }),
        setExpanded: (expanded: boolean) => ({ expanded }),
    }),
    loaders(({ values }) => ({
        spikes: [
            [] as TicketPatternApi[],
            {
                loadSpikes: async (_: void, breakpoint) => {
                    if (!values.bannerEnabled || !values.currentTeamId) {
                        return []
                    }
                    const spikes = await conversationsTicketPatternsList(String(values.currentTeamId))
                    // Every dismissal starts a reload, so two quick dismissals can resolve out of order.
                    // Only the newest reload may write the list, because an older one can still show a
                    // spike that was dismissed since.
                    breakpoint()
                    return spikes
                },
            },
        ],
    })),
    reducers({
        expanded: [false, { setExpanded: (_, { expanded }) => expanded }],
        // Hide the banner the moment it is clicked, rather than waiting for the reload to confirm.
        // The reload is what makes it stay hidden for everyone. A reload can land before a later
        // dismissal is saved, so a key stays pending until a reload shows that spike dismissed or gone.
        pendingDismissals: [
            [] as string[],
            {
                dismissSpike: (state, { key }) => [...state, key],
                dismissSpikeFailure: (state, { key }) => state.filter((pending) => pending !== key),
                loadSpikesSuccess: (state, { spikes }) =>
                    state.filter((key) => spikes.some((spike) => spike.key === key && !spike.dismissed_by)),
            },
        ],
    }),
    selectors({
        bannerEnabled: [
            (s) => [s.currentTeam, s.featureFlags],
            (currentTeam: TeamPublicType | TeamType | null, featureFlags: FeatureFlagsSet): boolean =>
                // The flag is the rollout lever, so the banner answers to it like detection and the
                // settings section do. Turning the flag off also hides the switch that owns the
                // banner, which would otherwise leave cached spikes on screen with no way to stop them.
                !!featureFlags[FEATURE_FLAGS.PRODUCT_SUPPORT_TICKET_PATTERNS] &&
                !!currentTeam?.conversations_settings?.ticket_patterns_enabled &&
                !!currentTeam?.conversations_settings?.ticket_patterns_banner_enabled,
        ],
        visibleSpikes: [
            (s) => [s.spikes, s.pendingDismissals],
            (spikes: TicketPatternApi[], pendingDismissals: string[]): TicketPatternApi[] =>
                spikes.filter((spike) => !spike.dismissed_by && !pendingDismissals.includes(spike.key)),
        ],
        dismissedSpikes: [
            (s) => [s.spikes, s.pendingDismissals],
            (spikes: TicketPatternApi[], pendingDismissals: string[]): TicketPatternApi[] =>
                spikes.filter((spike) => !!spike.dismissed_by || pendingDismissals.includes(spike.key)),
        ],
    }),
    listeners(({ actions, values }) => ({
        dismissSpike: async ({ key }) => {
            if (!values.currentTeamId) {
                return
            }
            try {
                await conversationsTicketPatternsDismissCreate(String(values.currentTeamId), { key })
            } catch {
                actions.dismissSpikeFailure(key)
                lemonToast.error('Could not dismiss the spike. Refresh and try again.')
            }
            actions.loadSpikes()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSpikes()
    }),
])
