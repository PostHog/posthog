import { MakeLogicType, actions, afterMount, connect, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import type { TeamPublicType, TeamType } from '../../../../../frontend/src/types'
import { conversationsTicketPatternsList } from '../../generated/api'
import type { TicketPatternApi } from '../../generated/api.schemas'

// A spike is dismissed by topic and detection time, so the same topic firing again later comes
// back rather than staying hidden forever.
export function spikeKey(spike: TicketPatternApi): string {
    return `${spike.topic}:${spike.detected_at}`
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketSpikeBannerLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    currentTeamId: number | null // teamLogic
    bannerEnabled: boolean
    dismissedKeys: string[]
    spikes: TicketPatternApi[]
    spikesLoading: boolean
    visibleSpikes: TicketPatternApi[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketSpikeBannerLogicActions {
    dismissSpike: (key: string) => {
        key: string
    }
    loadSpikes: () => any
    loadSpikesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSpikesSuccess: (
        spikes: TicketPatternApi[],
        payload?: any
    ) => {
        spikes: TicketPatternApi[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketSpikeBannerLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        bannerEnabled: (currentTeam: TeamPublicType | TeamType | null) => boolean
        visibleSpikes: (spikes: TicketPatternApi[], dismissedKeys: string[]) => TicketPatternApi[]
    }
}

export type ticketSpikeBannerLogicType = MakeLogicType<
    ticketSpikeBannerLogicValues,
    ticketSpikeBannerLogicActions,
    Record<string, any>,
    ticketSpikeBannerLogicMeta
>

export const ticketSpikeBannerLogic = kea<ticketSpikeBannerLogicType>([
    path(['products', 'conversations', 'frontend', 'components', 'TicketSpikeBanner', 'ticketSpikeBannerLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentTeamId']],
    })),
    actions({
        dismissSpike: (key: string) => ({ key }),
    }),
    loaders(({ values }) => ({
        spikes: [
            [] as TicketPatternApi[],
            {
                loadSpikes: async () => {
                    if (!values.bannerEnabled || !values.currentTeamId) {
                        return []
                    }
                    return await conversationsTicketPatternsList(String(values.currentTeamId))
                },
            },
        ],
    })),
    reducers({
        dismissedKeys: [
            [] as string[],
            { persist: true, storageKey: 'conversations_dismissed_ticket_spikes' },
            {
                // Capped so a long-running project cannot grow this without bound in local storage.
                dismissSpike: (state, { key }) => [key, ...state.filter((k) => k !== key)].slice(0, 50),
            },
        ],
    }),
    selectors({
        bannerEnabled: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): boolean =>
                !!currentTeam?.conversations_settings?.ticket_patterns_banner_enabled,
        ],
        visibleSpikes: [
            (s) => [s.spikes, s.dismissedKeys],
            (spikes: TicketPatternApi[], dismissedKeys: string[]): TicketPatternApi[] =>
                spikes.filter((spike) => !dismissedKeys.includes(spikeKey(spike))),
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadSpikes()
    }),
])
