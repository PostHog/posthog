import { MakeLogicType, actions, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { router, urlToAction } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import api, { ApiConfig } from 'lib/api'
import { urls } from 'scenes/urls'

import { personsRetrieve } from 'products/persons/frontend/generated/api'

import { conversationsTicketsComposeCreate } from '../../generated/api'
import type { EmailConfigStatus } from '../../scenes/settings/supportSettingsLogic'

export const COMPOSE_PERSON_URL_PARAM = 'compose_person'

function composeValidationError(message: string, recipientEmail: string, emailConfigId: string): string | null {
    if (!message.trim()) {
        return 'Message is required.'
    }
    if (!recipientEmail) {
        return 'Recipient email is required.'
    }
    if (!emailConfigId) {
        return 'Please select a "From" email address.'
    }
    return null
}

