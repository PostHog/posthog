export type composeTicketLogicType = MakeLogicType<composeTicketLogicValues, composeTicketLogicActions>

export const composeTicketLogic = kea<composeTicketLogicType>([
    path(['products', 'conversations', 'frontend', 'components', 'ComposeTicket', 'composeTicketLogic']),
    actions({
        openComposeModal: (prefill?: { distinctId?: string; email?: string }) => ({ prefill }),
        openComposeModalForPerson: (personUuid: string) => ({ personUuid }),
        closeComposeModal: true,
        setRecipientEmail: (email: string) => ({ email }),
        setRecipientDistinctId: (distinctId: string) => ({ distinctId }),
        setEmailSubject: (subject: string) => ({ subject }),
        setEmailConfigId: (configId: string, isManual: boolean = true) => ({ configId, isManual }),
        resetForm: true,
        submitCompose: (message: string, richContent: Record<string, unknown> | null) => ({ message, richContent }),
        submitComposeFinished: true,
    }),
    reducers({
        isOpen: [
            false,
            {
                openComposeModal: () => true,
                closeComposeModal: () => false,
                resetForm: () => false,
            },
        ],
        recipientEmail: [
            '',
            {
                setRecipientEmail: (_, { email }) => email,
                openComposeModal: () => '',
                resetForm: () => '',
            },
        ],
        recipientDistinctId: [
            '',
            {
                setRecipientDistinctId: (_, { distinctId }) => distinctId,
                openComposeModal: () => '',
                resetForm: () => '',
            },
        ],
        emailSubject: [
            '',
            {
                setEmailSubject: (_, { subject }) => subject,
                openComposeModal: () => '',
                resetForm: () => '',
            },
        ],
        emailConfigId: [
            '',
            {
                setEmailConfigId: (_, { configId }) => configId,
                openComposeModal: () => '',
                resetForm: () => '',
            },
        ],
        senderManuallySelected: [
            false,
            {
                setEmailConfigId: (_, { isManual }) => isManual,
                openComposeModal: () => false,
                resetForm: () => false,
            },
        ],
        composingLoading: [
            false,
            {
                submitCompose: () => true,
                submitComposeFinished: () => false,
                openComposeModal: () => false,
                resetForm: () => false,
            },
        ],
    }),
    loaders({
        emailConfigs: [
            [] as EmailConfigStatus[],
            {
                loadEmailConfigs: async (): Promise<EmailConfigStatus[]> => {
                    try {
                        // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                        const response = await api.get('api/conversations/v1/email/status')
                        return response.configs || []
                    } catch {
                        return []
                    }
                },
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openComposeModal: ({ prefill }) => {
            cache.composeSession = (cache.composeSession ?? 0) + 1
            if (prefill?.distinctId) {
                actions.setRecipientDistinctId(prefill.distinctId)
            }
            if (prefill?.email) {
                actions.setRecipientEmail(prefill.email)
            }
            actions.loadEmailConfigs()
        },
        openComposeModalForPerson: async ({ personUuid }) => {
            actions.openComposeModal()
            const session = cache.composeSession
            try {
                const person = await personsRetrieve(String(ApiConfig.getCurrentProjectId()), personUuid)
                // Drop the result if this draft closed, another draft opened, or the user entered a recipient.
                if (
                    session !== cache.composeSession ||
                    !values.isOpen ||
                    values.recipientEmail ||
                    values.recipientDistinctId
                ) {
                    return
                }
                const email = (person.properties as Record<string, unknown> | undefined)?.email
                if (person.distinct_ids[0]) {
                    actions.setRecipientDistinctId(person.distinct_ids[0])
                }
                if (typeof email === 'string') {
                    actions.setRecipientEmail(email)
                }
            } catch {
                lemonToast.error("Couldn't load this person. Enter the recipient's email to continue.")
            }
        },
        loadEmailConfigsSuccess: ({ emailConfigs }) => {
            // Default the "From" address to the team's primary channel (falling back to the first verified one).
            // Skip only when the user picked a sender themselves — a newer response can still re-apply the default,
            // so a stale in-flight request can't lock in an outdated sender.
            if (values.senderManuallySelected) {
                return
            }
            const verified = emailConfigs.filter((c) => c.domain_verified)
            const defaultConfig = verified.find((c) => c.is_default) ?? verified[0]
            if (defaultConfig) {
                actions.setEmailConfigId(defaultConfig.id, false)
            }
        },
        submitCompose: async ({ message, richContent }) => {
            const { recipientEmail, recipientDistinctId, emailSubject, emailConfigId } = values

            const validationError = composeValidationError(message, recipientEmail, emailConfigId)
            if (validationError) {
                lemonToast.error(validationError)
                actions.submitComposeFinished()
                return
            }

            try {
                const result = await conversationsTicketsComposeCreate(String(ApiConfig.getCurrentProjectId()), {
                    message,
                    recipient_email: recipientEmail,
                    email_config_id: emailConfigId,
                    ...(recipientDistinctId ? { recipient_distinct_id: recipientDistinctId } : {}),
                    ...(emailSubject ? { email_subject: emailSubject } : {}),
                    ...(richContent ? { rich_content: richContent } : {}),
                })

                lemonToast.success('Ticket created successfully.')
                actions.resetForm()
                router.actions.push(urls.supportTicketDetail(result.ticket_number))
            } catch (error: unknown) {
                const detail =
                    error && typeof error === 'object' && 'detail' in error
                        ? (error as { detail: string }).detail
                        : 'Failed to create ticket.'
                lemonToast.error(detail)
                actions.submitComposeFinished()
            }
        },
    })),
    urlToAction(({ actions }) => ({
        '/support/tickets': (_, searchParams) => {
            const personUuid = searchParams[COMPOSE_PERSON_URL_PARAM]
            if (!personUuid) {
                return
            }
            // Remove the param so a reload or a later filter change does not open the composer again.
            const { [COMPOSE_PERSON_URL_PARAM]: _personUuid, ...otherSearchParams } = searchParams
            router.actions.replace(router.values.location.pathname, otherSearchParams, router.values.hashParams)
            actions.openComposeModalForPerson(String(personUuid))
        },
    })),
])
