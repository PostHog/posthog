export const supportMacrosLogic = kea<supportMacrosLogicType>([
    path(['products', 'conversations', 'supportMacros']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        createMacro: (payload: MacroSavePayload) => payload,
        updateMacro: (payload: MacroSavePayload & { id: string }) => payload,
        deleteMacro: (id: string) => ({ id }),
        upsertMacro: (macro: TicketMacroApi) => ({ macro }),
        removeMacro: (id: string) => ({ id }),
        recordMacroUsed: (id: string) => ({ id }),
        openMacroDraft: (macro: TicketMacroApi | null) => ({ macro }),
        closeMacroDraft: true,
        setMacroDraftName: (name: string) => ({ name }),
        setMacroDraftShortcut: (shortcut: string) => ({ shortcut }),
        setMacroSaving: (saving: boolean) => ({ saving }),
    }),
    loaders(({ values }) => ({
        macros: [
            [] as TicketMacroApi[],
            {
                loadMacros: async () => {
                    if (!values.currentTeamId) {
                        return []
                    }
                    const collected: TicketMacroApi[] = []
                    let offset = 0
                    while (collected.length < 1000) {
                        const page = await conversationsMacrosList(String(values.currentTeamId), {
                            limit: 100,
                            offset,
                        })
                        collected.push(...page.results)
                        if (!page.next || page.results.length === 0) {
                            break
                        }
                        offset += page.results.length
                    }
                    return collected
                },
            },
        ],
    })),
    reducers({
        macros: {
            upsertMacro: (state, { macro }) => {
                const existing = state.some((item) => item.id === macro.id)
                return existing ? state.map((item) => (item.id === macro.id ? macro : item)) : [macro, ...state]
            },
            removeMacro: (state, { id }) => state.filter((item) => item.id !== id),
            recordMacroUsed: (state, { id }) =>
                state.map((item) =>
                    item.id === id
                        ? { ...item, usage_count: item.usage_count + 1, last_used_at: new Date().toISOString() }
                        : item
                ),
        },
        macroDraft: [
            null as MacroDraft | null,
            {
                openMacroDraft: (_, { macro }) => ({
                    id: macro?.id ?? null,
                    name: macro?.name ?? '',
                    shortcut: macro?.shortcut ?? '',
                    body: macro?.body ?? '',
                }),
                closeMacroDraft: () => null,
                setMacroDraftName: (state, { name }) => (state ? { ...state, name } : state),
                setMacroDraftShortcut: (state, { shortcut }) => (state ? { ...state, shortcut } : state),
            },
        ],
        macroSaving: [
            false,
            {
                setMacroSaving: (_, { saving }) => saving,
            },
        ],
    }),
    selectors({
        macrosEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.PRODUCT_SUPPORT_MACROS],
        ],
        macrosSorted: [
            (s) => [s.macros],
            (macros: TicketMacroApi[]): TicketMacroApi[] =>
                [...macros].sort((a, b) => b.usage_count - a.usage_count || a.name.localeCompare(b.name)),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadMacrosSuccess: () => {
            cache.loaded = true
        },
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
            if (values.macrosEnabled && !cache.loaded && !values.macrosLoading) {
                actions.loadMacros()
            }
        },
        createMacro: async ({ name, shortcut, body }) => {
            if (!values.currentTeamId) {
                return
            }
            const invalidShortcut = shortcutError(shortcut)
            if (invalidShortcut) {
                lemonToast.error(invalidShortcut)
                return
            }
            actions.setMacroSaving(true)
            try {
                const created = await conversationsMacrosCreate(String(values.currentTeamId), {
                    name: name.trim(),
                    shortcut: normalizeShortcut(shortcut),
                    body,
                })
                actions.upsertMacro(created)
                actions.closeMacroDraft()
                lemonToast.success('Macro saved')
            } catch (error) {
                lemonToast.error(macroErrorMessage(error, "Couldn't save the macro."))
            } finally {
                actions.setMacroSaving(false)
            }
        },
        updateMacro: async ({ id, name, shortcut, body }) => {
            if (!values.currentTeamId) {
                return
            }
            const invalidShortcut = shortcutError(shortcut)
            if (invalidShortcut) {
                lemonToast.error(invalidShortcut)
                return
            }
            actions.setMacroSaving(true)
            try {
                const updated = await conversationsMacrosPartialUpdate(String(values.currentTeamId), id, {
                    name: name.trim(),
                    shortcut: normalizeShortcut(shortcut),
                    body,
                })
                actions.upsertMacro(updated)
                actions.closeMacroDraft()
                lemonToast.success('Macro saved')
            } catch (error) {
                lemonToast.error(macroErrorMessage(error, "Couldn't save the macro."))
            } finally {
                actions.setMacroSaving(false)
            }
        },
        deleteMacro: async ({ id }) => {
            if (!values.currentTeamId) {
                return
            }
            try {
                await conversationsMacrosDestroy(String(values.currentTeamId), id)
                actions.removeMacro(id)
                lemonToast.success('Macro deleted')
            } catch (error) {
                lemonToast.error(macroErrorMessage(error, "Couldn't delete the macro."))
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.macrosEnabled) {
            actions.loadMacros()
        }
    }),
])
