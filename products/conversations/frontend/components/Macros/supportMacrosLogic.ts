const SHORTCUT_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/

export interface MacroDraft {
    id: string | null
    name: string
    shortcut: string
    body: string
}

export interface MacroSavePayload {
    name: string
    shortcut: string
    body: string
}

function normalizeShortcut(shortcut: string): string | null {
    const trimmed = shortcut.trim().toLowerCase()
    return trimmed ? trimmed : null
}

function macroErrorMessage(error: unknown, fallback: string): string {
    if (error instanceof ApiError && error.data && typeof error.data === 'object') {
        for (const value of Object.values(error.data as Record<string, unknown>)) {
            if (typeof value === 'string' && value) {
                return value
            }
            if (Array.isArray(value) && typeof value[0] === 'string') {
                return value[0]
            }
        }
        if (error.detail) {
            return error.detail
        }
    }
    return fallback
}

export function shortcutError(shortcut: string): string | null {
    const normalized = normalizeShortcut(shortcut)
    if (!normalized) {
        return null
    }
    if (!SHORTCUT_RE.test(normalized)) {
        return 'Use lowercase letters, numbers, and hyphens.'
    }
    return null
}

