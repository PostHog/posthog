import { MakeLogicType, actions, kea, listeners, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import {
    DEFAULT_TICKET_SIDEBAR_LAYOUT,
    StoredTicketSidebarLayout,
    TicketSidebarLayout,
    TicketSidebarWidgetKey,
    resolveTicketSidebarLayout,
    storeTicketSidebarLayout,
    ticketSidebarLayoutsEqual,
} from './ticketSidebarLayout'

// pinned: analytics event names. Renaming them breaks insights built on them.
const EDIT_STARTED_EVENT = 'support ticket sidebar edit started'
const EDIT_CANCELED_EVENT = 'support ticket sidebar edit canceled'
const LAYOUT_SAVED_EVENT = 'support ticket sidebar layout saved'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketSidebarWidgetsLogicValues {
    userLayout: StoredTicketSidebarLayout | null
    draft: TicketSidebarLayout | null
    isEditing: boolean
    layout: TicketSidebarLayout
    draftMatchesDefault: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface ticketSidebarWidgetsLogicActions {
    startEditing: () => {
        value: true
    }
    cancelEditing: () => {
        value: true
    }
    setDraft: (draft: TicketSidebarLayout | null) => {
        draft: TicketSidebarLayout | null
    }
    moveWidget: (
        fromIndex: number,
        toIndex: number
    ) => {
        fromIndex: number
        toIndex: number
    }
    hideWidget: (key: TicketSidebarWidgetKey) => {
        key: TicketSidebarWidgetKey
    }
    showWidget: (key: TicketSidebarWidgetKey) => {
        key: TicketSidebarWidgetKey
    }
    resetDraftToDefault: () => {
        value: true
    }
    saveLayout: () => {
        value: true
    }
    setUserLayout: (layout: StoredTicketSidebarLayout | null) => {
        layout: StoredTicketSidebarLayout | null
    }
}

export type ticketSidebarWidgetsLogicType = MakeLogicType<
    ticketSidebarWidgetsLogicValues,
    ticketSidebarWidgetsLogicActions
>

export const ticketSidebarWidgetsLogic = kea<ticketSidebarWidgetsLogicType>([
    // pinned: the path is part of the localStorage key of the persisted userLayout. Changing it resets saved layouts.
    path(['products', 'conversations', 'frontend', 'components', 'TicketSidebarWidgets', 'ticketSidebarWidgetsLogic']),
    actions({
        startEditing: true,
        cancelEditing: true,
        setDraft: (draft: TicketSidebarLayout | null) => ({ draft }),
        moveWidget: (fromIndex: number, toIndex: number) => ({ fromIndex, toIndex }),
        hideWidget: (key: TicketSidebarWidgetKey) => ({ key }),
        showWidget: (key: TicketSidebarWidgetKey) => ({ key }),
        resetDraftToDefault: true,
        saveLayout: true,
        setUserLayout: (layout: StoredTicketSidebarLayout | null) => ({ layout }),
    }),
    reducers({
        userLayout: [
            null as StoredTicketSidebarLayout | null,
            { persist: true },
            {
                setUserLayout: (_, { layout }) => layout,
            },
        ],
        draft: [
            null as TicketSidebarLayout | null,
            {
                setDraft: (_, { draft }) => draft,
                cancelEditing: () => null,
                setUserLayout: () => null,
                moveWidget: (state, { fromIndex, toIndex }) => {
                    const inRange = (index: number): boolean => index >= 0 && index < (state?.visible.length ?? 0)
                    if (!state || fromIndex === toIndex || !inRange(fromIndex) || !inRange(toIndex)) {
                        return state
                    }
                    const visible = [...state.visible]
                    const [moved] = visible.splice(fromIndex, 1)
                    visible.splice(toIndex, 0, moved)
                    return { ...state, visible }
                },
                hideWidget: (state, { key }) =>
                    state && state.visible.includes(key)
                        ? { visible: state.visible.filter((k) => k !== key), hidden: [...state.hidden, key] }
                        : state,
                showWidget: (state, { key }) =>
                    state && state.hidden.includes(key)
                        ? { visible: [...state.visible, key], hidden: state.hidden.filter((k) => k !== key) }
                        : state,
            },
        ],
    }),
    selectors({
        isEditing: [(s) => [s.draft], (draft): boolean => draft !== null],
        layout: [
            (s) => [s.draft, s.userLayout],
            (draft, userLayout): TicketSidebarLayout => draft ?? resolveTicketSidebarLayout(userLayout),
        ],
        draftMatchesDefault: [
            (s) => [s.draft],
            (draft): boolean => !!draft && ticketSidebarLayoutsEqual(draft, DEFAULT_TICKET_SIDEBAR_LAYOUT),
        ],
    }),
    listeners(({ actions, values }) => ({
        startEditing: () => {
            actions.setDraft(values.layout)
            posthog.capture(EDIT_STARTED_EVENT, { has_saved_layout: values.userLayout !== null })
        },
        cancelEditing: () => {
            posthog.capture(EDIT_CANCELED_EVENT)
        },
        resetDraftToDefault: () => {
            actions.setDraft(DEFAULT_TICKET_SIDEBAR_LAYOUT)
        },
        saveLayout: () => {
            const { draft, draftMatchesDefault } = values
            if (!draft) {
                return
            }
            posthog.capture(LAYOUT_SAVED_EVENT, { visible_widgets: draft.visible, hidden_widgets: draft.hidden })
            // Saving the default stores nothing, so the user keeps getting later changes to the default order.
            actions.setUserLayout(draftMatchesDefault ? null : storeTicketSidebarLayout(draft))
        },
    })),
])
