export const ticketSidebarWidgetsLogic = kea<ticketSidebarWidgetsLogicType>([
    path(['products', 'conversations', 'frontend', 'components', 'TicketSidebarWidgets', 'ticketSidebarWidgetsLogic']),
    connect(() => ({
        values: [uiCustomizationLogic, ['uiConfiguration']],
        actions: [uiCustomizationLogic, ['updateUiConfiguration']],
    })),
    actions({
        startEditing: true,
        cancelEditing: true,
        setDraft: (draft: TicketSidebarLayout | null) => ({ draft }),
        moveWidget: (fromIndex: number, toIndex: number) => ({ fromIndex, toIndex }),
        hideWidget: (key: TicketSidebarWidgetKey) => ({ key }),
        showWidget: (key: TicketSidebarWidgetKey) => ({ key }),
        resetDraftToDefault: true,
        saveLayout: true,
    }),
    reducers({
        draft: [
            null as TicketSidebarLayout | null,
            {
                setDraft: (_, { draft }) => draft,
                cancelEditing: () => null,
                moveWidget: (state, { fromIndex, toIndex }) => {
                    const inRange = (index: number): boolean => index >= 0 && index < (state?.visible.length ?? 0)
                    if (!state || fromIndex === toIndex || !inRange(fromIndex) || !inRange(toIndex)) {
                        return state
                    }
                    const visible = [...state.visible]
                    const [moved] = visible.splice(fromIndex, 1)
                    visible.splice(toIndex, 0, moved)
                    return { ...state, visible }
                },
                hideWidget: (state, { key }) =>
                    state && state.visible.includes(key)
                        ? { visible: state.visible.filter((k) => k !== key), hidden: [...state.hidden, key] }
                        : state,
                showWidget: (state, { key }) =>
                    state && state.hidden.includes(key)
                        ? { visible: [...state.visible, key], hidden: state.hidden.filter((k) => k !== key) }
                        : state,
            },
        ],
    }),
    selectors({
        userLayout: [
            (s) => [s.uiConfiguration],
            (uiConfiguration: UserUIConfiguration | null): TicketSidebarConfiguration | null =>
                uiConfiguration?.ticket_sidebar ?? null,
        ],
        isEditing: [(s) => [s.draft], (draft: TicketSidebarLayout | null): boolean => draft !== null],
        layout: [
            (s) => [s.draft, s.userLayout],
            (draft: TicketSidebarLayout | null, userLayout: TicketSidebarConfiguration | null): TicketSidebarLayout =>
                draft ?? resolveTicketSidebarLayout(userLayout),
        ],
        draftMatchesDefault: [
            (s) => [s.draft],
            (draft: TicketSidebarLayout | null): boolean =>
                !!draft && ticketSidebarLayoutsEqual(draft, DEFAULT_TICKET_SIDEBAR_LAYOUT),
        ],
    }),
    listeners(({ actions, values }) => ({
        startEditing: () => {
            actions.setDraft(values.layout)
            posthog.capture(EDIT_STARTED_EVENT, { has_saved_layout: values.userLayout !== null })
        },
        cancelEditing: () => {
            posthog.capture(EDIT_CANCELED_EVENT)
        },
        resetDraftToDefault: () => {
            actions.setDraft(DEFAULT_TICKET_SIDEBAR_LAYOUT)
        },
        saveLayout: () => {
            const { draft, draftMatchesDefault, uiConfiguration } = values
            if (!draft) {
                return
            }
            posthog.capture(LAYOUT_SAVED_EVENT, { visible_widgets: draft.visible, hidden_widgets: draft.hidden })
            // The server replaces ui_configuration wholesale, so every other key is carried over.
            // Saving the default stores nothing, so the user keeps getting later changes to the default order.
            actions.updateUiConfiguration({
                version: UI_CONFIGURATION_VERSION,
                ...uiConfiguration,
                ticket_sidebar: draftMatchesDefault ? undefined : storeTicketSidebarLayout(draft),
            })
            actions.setDraft(null)
        },
    })),
])
