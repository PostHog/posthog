export const ticketViewsLogic = kea<ticketViewsLogicType>([
    props({} as TicketViewsLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'conversations', 'frontend', 'components', 'SavedViews', 'ticketViewsLogic', key]),

    connect(() => ({
        values: [teamLogic, ['currentTeamId'], supportTicketsSceneLogic, ['currentFilters', 'activeView']],
        actions: [supportTicketsSceneLogic, ['applyView', 'setActiveView']],
    })),

    actions({
        deleteView: (shortId: string) => ({ shortId }),
        updateView: (shortId: string, changes: TicketViewChanges) => ({ shortId, changes }),
        viewUpdated: (view: SavedTicketView) => ({ view }),
        toggleFavorite: (view: SavedTicketView) => ({ view }),
        loadView: (view: SavedTicketView) => ({ view }),
        openModal: true,
        closeModal: true,
        openSaveModal: true,
        closeSaveModal: true,
        setViewName: (viewName: string) => ({ viewName }),
        saveView: true,
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        moveViewToFolder: (shortId: string, folder: string) => ({ shortId, folder }),
        moveFolder: (fromFolder: string, toFolder: string) => ({ fromFolder, toFolder }),
        moveFolderComplete: (fromFolder: string) => ({ fromFolder }),
        renameFolder: (fromFolder: string, newName: string) => ({ fromFolder, newName }),
        setExpandedFolderIds: (ids: string[]) => ({ ids }),
        toggleFolderExpanded: (id: string) => ({ id }),
        revealFolder: (path: string) => ({ path }),
    }),

    loaders(({ values }) => ({
        views: [
            [] as SavedTicketView[],
            {
                loadViews: async () => {
                    // The folder tree groups client-side, so it needs every view — a single page
                    // would render a silently truncated tree. Follow the server's own page size
                    // rather than assuming one here.
                    const teamId = String(values.currentTeamId)
                    const collected: SavedTicketView[] = []
                    for (let page = 0; page < MAX_VIEW_PAGES; page++) {
                        const response = await conversationsViewsList(teamId, { offset: collected.length })
                        const results = (response.results ?? []) as unknown as SavedTicketView[]
                        collected.push(...results)
                        if (!response.next || !results.length) {
                            break
                        }
                    }
                    return collected
                },
                createView: async ({ name, filters }: { name: string; filters: TicketViewFilters }) => {
                    const created = (await conversationsViewsCreate(String(values.currentTeamId), {
                        name,
                        filters: filters as TicketViewFiltersApi,
                    })) as unknown as SavedTicketView
                    lemonToast.success('View saved')
                    return [created, ...values.views]
                },
            },
        ],
    })),

    reducers({
        views: {
            deleteView: (state, { shortId }) => state.filter((v) => v.short_id !== shortId),
            viewUpdated: (state, { view }) => state.map((v) => (v.short_id === view.short_id ? view : v)),
        },
        favoritingShortIds: [
            [] as string[],
            {
                toggleFavorite: (state, { view }) =>
                    state.includes(view.short_id) ? state : [...state, view.short_id],
                viewUpdated: (state, { view }) => state.filter((id) => id !== view.short_id),
                // Clear on load completion (not the trigger) so opening the dropdown/modal
                // mid-flight doesn't drop the in-flight state early; also covers the
                // updateView failure path, which reloads views.
                loadViewsSuccess: () => [],
                loadViewsFailure: () => [],
            },
        ],
        isModalOpen: [
            false,
            {
                openModal: () => true,
                closeModal: () => false,
                loadView: () => false,
            },
        ],
        isSaveModalOpen: [
            false,
            {
                openSaveModal: () => true,
                closeSaveModal: () => false,
                createViewSuccess: () => false,
            },
        ],
        viewName: [
            '',
            {
                setViewName: (_, { viewName }) => viewName,
                closeSaveModal: () => '',
                createViewSuccess: () => '',
            },
        ],
        searchTerm: [
            '',
            {
                setSearchTerm: (_, { searchTerm }) => searchTerm,
                openModal: () => '',
                closeModal: () => '',
            },
        ],
        // Which folders a person left open is a per-user, per-team preference, so it outlives the
        // modal and the page. The logic path already carries props.id, keeping each surface separate.
        expandedFolderIds: [
            [] as string[],
            { persist: true, prefix: `${getCurrentTeamIdOrNone() ?? 'none'}__` },
            {
                setExpandedFolderIds: (_, { ids }) => ids,
                toggleFolderExpanded: (state, { id }) =>
                    state.includes(id) ? state.filter((existing) => existing !== id) : [...state, id],
                revealFolder: (state, { path }) => [...new Set([...state, ...ancestorFolderNodeIds(path)])],
            },
        ],
        movingFolders: [
            [] as string[],
            {
                moveFolder: (state, { fromFolder }) => (state.includes(fromFolder) ? state : [...state, fromFolder]),
                moveFolderComplete: (state, { fromFolder }) => state.filter((existing) => existing !== fromFolder),
                loadViewsSuccess: () => [],
                loadViewsFailure: () => [],
            },
        ],
    }),

    selectors({
        sortedViews: [
            (s) => [s.views],
            (views: SavedTicketView[]): SavedTicketView[] =>
                [...views].sort((a, b) => {
                    if (a.is_favorited !== b.is_favorited) {
                        return a.is_favorited ? -1 : 1
                    }
                    return b.created_at.localeCompare(a.created_at)
                }),
        ],
        favoriteViews: [
            (s) => [s.sortedViews],
            (sortedViews: SavedTicketView[]): SavedTicketView[] => sortedViews.filter((v) => v.is_favorited),
        ],
        filteredViews: [
            (s) => [s.sortedViews, s.searchTerm],
            (sortedViews: SavedTicketView[], searchTerm: string): SavedTicketView[] =>
                searchViews(sortedViews, searchTerm),
        ],
        folderPaths: [(s) => [s.views], (views: SavedTicketView[]): string[] => ticketViewFolderPaths(views)],
        // The dropdown keeps its own flat Favorites section, so its folder tree leaves them out.
        folderMenuTree: [
            (s) => [s.sortedViews],
            (sortedViews: SavedTicketView[]): TreeDataItem[] => buildTicketViewTree(sortedViews),
        ],
        viewTree: [
            (s) => [s.sortedViews, s.searchTerm, s.filteredViews],
            (sortedViews: SavedTicketView[], searchTerm: string, filteredViews: SavedTicketView[]): TreeDataItem[] =>
                buildTicketViewTree(sortedViews, {
                    includeFavorites: true,
                    matches: searchTerm ? filteredViews : null,
                }),
        ],
        // While searching, reveal every match instead of the folders the person last left open.
        effectiveExpandedFolderIds: [
            (s) => [s.expandedFolderIds, s.searchTerm, s.filteredViews],
            (expandedFolderIds: string[], searchTerm: string, filteredViews: SavedTicketView[]): string[] =>
                searchTerm
                    ? [
                          FAVORITES_NODE_ID,
                          ...new Set(filteredViews.flatMap((view) => ancestorFolderNodeIds(view.folder))),
                      ]
                    : expandedFolderIds,
        ],
    }),

    listeners(({ actions, values }) => ({
        toggleFavorite: ({ view }) => {
            actions.updateView(view.short_id, { is_favorited: !view.is_favorited })
        },
        openModal: () => {
            // The header dropdown already loads views on open; skip a duplicate GET if one is in flight
            if (!values.viewsLoading) {
                actions.loadViews()
            }
        },
        saveView: () => {
            const name = values.viewName.trim()
            if (!name) {
                return
            }
            actions.createView({ name, filters: { ...values.currentFilters } })
        },
        deleteView: async ({ shortId }) => {
            try {
                await conversationsViewsDestroy(String(values.currentTeamId), shortId)
                lemonToast.success('View deleted')
            } catch {
                lemonToast.error('Failed to delete view')
                actions.loadViews()
            }
        },
        updateView: async ({ shortId, changes }) => {
            try {
                const updated = (await conversationsViewsPartialUpdate(
                    String(values.currentTeamId),
                    shortId,
                    changes as PatchedTicketViewApi
                )) as unknown as SavedTicketView
                actions.viewUpdated(updated)
                // Keep the header indicator and URL state in sync when the loaded view changes
                if (values.activeView?.short_id === shortId) {
                    actions.setActiveView(updated)
                }
                // Favoriting is a quiet, high-frequency action — no toast for it
                const isFavoriteToggleOnly = Object.keys(changes).length === 1 && 'is_favorited' in changes
                const isFolderChangeOnly = Object.keys(changes).length === 1 && 'folder' in changes
                if (isFolderChangeOnly) {
                    lemonToast.success(
                        changes.folder ? `View moved to "${changes.folder}"` : 'View moved to the top level'
                    )
                } else if (!isFavoriteToggleOnly) {
                    lemonToast.success('View updated')
                }
            } catch {
                lemonToast.error('Failed to update view')
                actions.loadViews()
            }
        },
        loadView: ({ view }) => {
            actions.applyView(view)
        },
        moveViewToFolder: ({ shortId, folder }) => {
            actions.updateView(shortId, { folder })
        },
        moveFolder: async ({ fromFolder, toFolder }) => {
            try {
                await conversationsViewsMoveFolderCreate(String(values.currentTeamId), {
                    from_folder: fromFolder,
                    to_folder: toFolder,
                })
                lemonToast.success(
                    toFolder ? `Folder moved to "${toFolder}"` : 'Folder removed. Its views moved to the top level.'
                )
                // Reload rather than rewriting paths here, so the server stays the authority on
                // how a folder path is normalized.
                actions.loadViews()
            } catch {
                lemonToast.error('Failed to move folder')
                actions.loadViews()
            } finally {
                actions.moveFolderComplete(fromFolder)
            }
        },
        renameFolder: ({ fromFolder, newName }) => {
            const trimmed = newName.trim()
            if (!trimmed) {
                return
            }
            // A rename is a move that keeps the parent, so it goes through the one endpoint.
            actions.moveFolder(fromFolder, joinPath([...splitPath(parentPath(fromFolder)), trimmed]))
        },
        createViewFailure: () => {
            lemonToast.error('Failed to save view')
        },
        loadViewsFailure: () => {
            lemonToast.error('Failed to load saved views')
        },
    })),
])
