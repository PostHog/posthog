import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { LemonSelectOption, LemonSelectOptions, lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { annotationsModel, deserializeAnnotation } from '~/models/annotationsModel'
import { AnnotationScope, AnnotationType, RawAnnotationType } from '~/types'

import { annotationsRetrieve } from '../generated/api'
import { annotationModalHostLogic } from './annotationModalHostLogic'
import { annotationScopeToName } from './annotationScopes'

const isValidAnnotationScope = (scope: string): scope is AnnotationScope => {
    return Object.values(AnnotationScope).includes(scope as AnnotationScope)
}

export const annotationScopesMenuOptions = (): LemonSelectOptions<AnnotationType['scope'] | null> => {
    const scopeOptions: LemonSelectOption<AnnotationType['scope'] | null>[] = Object.values(AnnotationScope).map(
        (scope) => ({
            value: scope,
            label: annotationScopeToName[scope],
        })
    )
    // add any with value null as the first option
    scopeOptions.unshift({
        value: null,
        label: 'Any',
    })
    return scopeOptions
}

