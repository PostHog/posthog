export type annotationModalLogicType = MakeLogicType<annotationModalLogicValues, annotationModalLogicActions>

export const annotationModalLogic = kea<annotationModalLogicType>([
    path(['scenes', 'annotations', 'annotationModalLogic']),
    connect(() => ({
        actions: [
            annotationModalHostLogic,
            [
                'openModalToCreateAnnotation as openHostModalToCreateAnnotation',
                'openModalToEditAnnotation as openHostModalToEditAnnotation',
            ],
        ],
        values: [teamLogic, ['timezone'], userLogic, ['user']],
    })),
    actions({
        openModalToCreateAnnotation: (
            initialDate?: Dayjs | null,
            insightId?: InsightModel['id'] | null,
            dashboardId?: DashboardBasicType['id'] | null
        ) => ({
            initialDate,
            insightId,
            dashboardId,
        }),
        openModalToEditAnnotation: (
            annotation: AnnotationType,
            insightId?: InsightModel['id'] | null,
            dashboardId?: DashboardBasicType['id'] | null
        ) => ({
            annotation,
            insightId,
            dashboardId,
        }),
        closeModal: true,
        deleteAnnotation: (annotation: AnnotationType) => ({ annotation }),
        setScope: (scope: AnnotationType['scope'] | null) => ({ scope }),
    }),
    reducers(() => ({
        scope: [null as AnnotationType['scope'] | null, { setScope: (_, { scope }) => scope }],
        isModalOpen: [
            false,
            {
                openModalToCreateAnnotation: () => true,
                openModalToEditAnnotation: () => true,
                closeModal: () => false,
            },
        ],
        existingModalAnnotation: [
            null as AnnotationType | null,
            {
                openModalToCreateAnnotation: () => null,
                openModalToEditAnnotation: (_, { annotation }) => annotation,
            },
        ],
        onSavedInsight: [
            false,
            {
                openModalToCreateAnnotation: (_, { insightId }) => !!insightId,
                openModalToEditAnnotation: (_, { insightId }) => !!insightId,
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        openModalToEditAnnotation: ({ annotation, insightId, dashboardId }) => {
            actions.resetAnnotationModal({
                dateMarker: dayjs(annotation.date_marker).tz(values.timezone),
                scope: annotation.scope,
                content: annotation.content,
                emoji: annotation.emoji,
                dashboardItemId: insightId ?? annotation.dashboard_item ?? null,
                dashboardId: dashboardId ?? annotation.dashboard_id ?? null,
            })
        },
        openModalToCreateAnnotation: ({ initialDate, insightId, dashboardId }) => {
            actions.resetAnnotationModal({
                dateMarker: initialDate ?? dayjs().tz(values.timezone),
                scope: AnnotationScope.Project,
                content: '',
                emoji: null,
                dashboardItemId: insightId ?? null,
                dashboardId: dashboardId ?? null,
            })
        },
        openHostModalToCreateAnnotation: ({ initialDate, insightId, dashboardId }) => {
            actions.openModalToCreateAnnotation(initialDate, insightId, dashboardId)
        },
        openHostModalToEditAnnotation: ({ annotation, insightId, dashboardId }) => {
            if (annotation) {
                actions.openModalToEditAnnotation(annotation, insightId, dashboardId)
            }
        },
        deleteAnnotation: ({ annotation }) => annotationsModel.actions.deleteAnnotation(annotation),
        closeModal: () => annotationModalHostLogic.actions.closeModal(),
    })),
    forms(({ actions, values }) => ({
        annotationModal: {
            defaults: {
                dateMarker: dayjs().tz(values.timezone),
                content: '',
                emoji: null,
                scope: AnnotationScope.Project,
                dashboardItemId: null,
                dashboardId: null,
            } as AnnotationModalForm,
            errors: ({ content }) => ({
                content: !content?.trim() ? 'An annotation must have text content.' : null,
            }),
            submit: async (data) => {
                const { dateMarker, content, emoji, scope, dashboardItemId, dashboardId } = data

                if (values.existingModalAnnotation) {
                    // annotationsModel's updateAnnotation inlined so that isAnnotationModalSubmitting works
                    const updatedAnnotation = await api.annotations.update(values.existingModalAnnotation.id, {
                        date_marker: dateMarker.toISOString(),
                        content,
                        emoji: emoji || null,
                        scope,
                        // update to new insight we're saving from
                        dashboard_item: dashboardItemId,
                        dashboard_id:
                            scope === AnnotationScope.Dashboard
                                ? dashboardId
                                : values.existingModalAnnotation.dashboard_id,
                    })
                    annotationsModel.actions.replaceAnnotation(updatedAnnotation)
                } else {
                    // annotationsModel's createAnnotationGenerically inlined so that isAnnotationModalSubmitting works
                    const createdAnnotation = await api.annotations.create({
                        date_marker: dateMarker.toISOString(),
                        content,
                        emoji: emoji || null,
                        scope,
                        dashboard_item: dashboardItemId,
                        dashboard_id: dashboardId,
                    })
                    annotationsModel.actions.appendAnnotations([createdAnnotation])
                    const trimmedContent = content?.trim() ?? ''
                    const snippet = trimmedContent.length > 60 ? trimmedContent.slice(0, 57) + '…' : trimmedContent
                    const date = dateMarker.format('YYYY-MM-DD')
                    tryShowMCPHint('annotations.create', {
                        derivedPrompt: snippet ? `Annotate ${date}: ${snippet}` : undefined,
                    })
                }
                actions.closeModal()
            },
        },
    })),
    afterMount(({ actions }) => {
        const request = annotationModalHostLogic.values.modalRequest
        if (!request) {
            return
        }
        if (request.annotation) {
            actions.openModalToEditAnnotation(request.annotation, request.insightId, request.dashboardId)
            return
        }
        actions.openModalToCreateAnnotation(request.initialDate, request.insightId, request.dashboardId)
    }),
])
