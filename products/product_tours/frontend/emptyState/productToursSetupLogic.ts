export type productToursSetupLogicType = MakeLogicType<productToursSetupLogicValues, productToursSetupLogicActions>

/**
 * Setup detection for the product tours empty state. Tours are a creation-first
 * product, so "set up" simply means the project has at least one tour - no event
 * or traffic signal involved. Re-checks on every mount (the scene gate mounts it),
 * which covers returning from the tour editor.
 *
 * Also owns the empty state's primary action: the list scene's own "New" button
 * opens an in-scene modal, which can't render while the gate replaces the scene,
 * and `/product_tours/new` has no working save path. So `createFirstTour` creates
 * a tour directly (same call the modal makes) and lands the user in the editor.
 */
export const productToursSetupLogic = kea<productToursSetupLogicType>([
    path(['products', 'product_tours', 'frontend', 'emptyState', 'productToursSetupLogic']),
    connect(() => ({
        actions: [productSetupStatusLogic({ productKey: ProductKey.PRODUCT_TOURS }), ['setDetectedStatus']],
        values: [
            productSetupStatusLogic({ productKey: ProductKey.PRODUCT_TOURS }),
            ['status as setupStatus'],
            teamLogic,
            ['currentProjectId'],
        ],
    })),
    actions({
        createFirstTour: true,
        setCreatingFirstTour: (creating: boolean) => ({ creating }),
    }),
    loaders(({ values }) => ({
        tourCount: [
            null as number | null,
            {
                loadTourCount: async (_: void, breakpoint): Promise<number> => {
                    const response = await productToursList(String(values.currentProjectId), { limit: 1 })
                    breakpoint()
                    return response.count
                },
            },
        ],
    })),
    reducers({
        creatingFirstTour: [
            false,
            {
                setCreatingFirstTour: (_, { creating }) => creating,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        loadTourCountSuccess: ({ tourCount }) => {
            actions.setDetectedStatus(tourCount !== null && tourCount > 0 ? 'has-data' : 'needs-setup')
        },
        loadTourCountFailure: () => {
            // Never strand the gate on its spinner: if nothing has answered yet, fail
            // open to the real scene. Don't downgrade an existing answer on a blip.
            if (values.setupStatus === 'loading') {
                actions.setDetectedStatus('unknown')
            }
        },
        createFirstTour: async () => {
            // The empty state's primary button has no loading wiring, so guard against
            // a double click creating two tours.
            if (values.creatingFirstTour) {
                return
            }
            actions.setCreatingFirstTour(true)
            try {
                const tour = await productToursCreate(String(values.currentProjectId), {
                    name: 'My first tour',
                    content: createDefaultTourContent(),
                })
                void addProductIntent({
                    product_type: ProductKey.PRODUCT_TOURS,
                    intent_context: ProductIntentContext.PRODUCT_TOUR_CREATED,
                })
                router.actions.push(urls.productTour(tour.id, 'edit=true'))
            } catch {
                lemonToast.error("Couldn't create the tour. Try again.")
            } finally {
                actions.setCreatingFirstTour(false)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadTourCount()
    }),
])
