import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { projectLogic } from 'scenes/projectLogic'

import { cloudAgentsRunsList } from '../generated/api'
import type {
    CloudAgentRunApi,
    CloudAgentRunStatusEnumApi,
    PaginatedCloudAgentRunListApi,
} from '../generated/api.schemas'
import { isRunActive } from '../utils/runStatus'

export const RUNS_PAGE_SIZE = 50
export const RUNS_REFRESH_INTERVAL_MS = 5000

export interface RunsFilters {
    status: CloudAgentRunStatusEnumApi | null
    presetId: string | null
    repository: string
}

const DEFAULT_FILTERS: RunsFilters = { status: null, presetId: null, repository: '' }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface cloudAgentsRunsLogicValues {
    currentProjectId: number | null // projectLogic
    filters: RunsFilters
    hasActiveRuns: boolean
    hasFilters: boolean
    page: number
    runs: CloudAgentRunApi[]
    runsCount: number
    runsLoadFailed: boolean
    runsPage: PaginatedCloudAgentRunListApi | null
    runsPageLoading: boolean
    runsTableLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface cloudAgentsRunsLogicActions {
    loadRuns: (_: void) => void
    loadRunsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRunsSuccess: (
        runsPage: PaginatedCloudAgentRunListApi,
        payload?: void
    ) => {
        runsPage: PaginatedCloudAgentRunListApi
        payload?: void
    }
    refreshRuns: () => any
    refreshRunsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    refreshRunsSuccess: (
        runsPage: PaginatedCloudAgentRunListApi,
        payload?: any
    ) => {
        runsPage: PaginatedCloudAgentRunListApi
        payload?: any
    }
    setFilters: (filters: Partial<RunsFilters>) => {
        filters: Partial<RunsFilters>
    }
    setPage: (page: number) => {
        page: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface cloudAgentsRunsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        runs: (runsPage: PaginatedCloudAgentRunListApi | null) => CloudAgentRunApi[]
        runsCount: (runsPage: PaginatedCloudAgentRunListApi | null) => number
        hasActiveRuns: (runs: CloudAgentRunApi[]) => boolean
        hasFilters: (filters: RunsFilters) => boolean
    }
}

export type cloudAgentsRunsLogicType = MakeLogicType<
    cloudAgentsRunsLogicValues,
    cloudAgentsRunsLogicActions,
    Record<string, any>,
    cloudAgentsRunsLogicMeta
>

async function fetchRuns(
    projectId: number | null,
    page: number,
    filters: RunsFilters
): Promise<PaginatedCloudAgentRunListApi> {
    return await cloudAgentsRunsList(String(projectId), {
        limit: RUNS_PAGE_SIZE,
        offset: (page - 1) * RUNS_PAGE_SIZE,
        ...(filters.status ? { status: filters.status } : {}),
        ...(filters.presetId ? { preset_id: filters.presetId } : {}),
        ...(filters.repository.trim() ? { repository: filters.repository.trim() } : {}),
    })
}

export const cloudAgentsRunsLogic = kea<cloudAgentsRunsLogicType>([
    path(['products', 'cloud_agents', 'frontend', 'logics', 'cloudAgentsRunsLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        setFilters: (filters: Partial<RunsFilters>) => ({ filters }),
        setPage: (page: number) => ({ page }),
    }),
    loaders(({ values }) => ({
        runsPage: [
            null as PaginatedCloudAgentRunListApi | null,
            {
                loadRuns: async (_: void, breakpoint): Promise<PaginatedCloudAgentRunListApi> => {
                    // The repository filter sends a request for each change, so wait for the typing to stop.
                    await breakpoint(250)
                    const response = await fetchRuns(values.currentProjectId, values.page, values.filters)
                    breakpoint()
                    return response
                },
                refreshRuns: async (): Promise<PaginatedCloudAgentRunListApi> =>
                    await fetchRuns(values.currentProjectId, values.page, values.filters),
            },
        ],
    })),
    reducers({
        filters: [DEFAULT_FILTERS, { setFilters: (state, { filters }) => ({ ...state, ...filters }) }],
        page: [1, { setPage: (_, { page }) => page, setFilters: () => 1 }],
        runsLoadFailed: [false, { loadRuns: () => false, loadRunsSuccess: () => false, loadRunsFailure: () => true }],
        // A background refresh must not put the table into its loading state every few seconds.
        runsTableLoading: [
            true,
            {
                loadRuns: () => true,
                loadRunsSuccess: () => false,
                loadRunsFailure: () => false,
            },
        ],
    }),
    selectors({
        runs: [
            (s) => [s.runsPage],
            (runsPage: PaginatedCloudAgentRunListApi | null): CloudAgentRunApi[] => runsPage?.results ?? [],
        ],
        runsCount: [
            (s) => [s.runsPage],
            (runsPage: PaginatedCloudAgentRunListApi | null): number => runsPage?.count ?? 0,
        ],
        hasActiveRuns: [
            (s) => [s.runs],
            (runs: CloudAgentRunApi[]): boolean => runs.some((run) => isRunActive(run.status)),
        ],
        hasFilters: [
            (s) => [s.filters],
            (filters: RunsFilters): boolean => !!filters.status || !!filters.presetId || !!filters.repository.trim(),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const scheduleRefresh = (): void => {
            if (!values.hasActiveRuns) {
                cache.disposables.dispose('refresh')
                return
            }
            cache.disposables.add(() => {
                const timer = window.setTimeout(() => actions.refreshRuns(), RUNS_REFRESH_INTERVAL_MS)
                return () => window.clearTimeout(timer)
            }, 'refresh')
        }
        return {
            setFilters: () => actions.loadRuns(),
            setPage: () => actions.loadRuns(),
            loadRunsSuccess: scheduleRefresh,
            refreshRunsSuccess: scheduleRefresh,
            // One failed refresh must not stop the refreshes: the next one can succeed.
            refreshRunsFailure: scheduleRefresh,
        }
    }),
    afterMount(({ actions }) => {
        actions.loadRuns()
    }),
])
