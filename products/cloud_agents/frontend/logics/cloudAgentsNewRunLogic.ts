/** The search parameter that opens the modal, so "start a run" has a link. */
export const NEW_RUN_SEARCH_PARAM = 'new_run'

/** The length of the example in the cost line under the box size select. */
export const COST_EXAMPLE_MINUTES = 15

export interface NewRunForm {
    prompt: string
    repository: string
    branch: string
    preset: string | null
    model: string | null
    reasoning_effort: CloudAgentReasoningEffortEnumApi | null
    size: SizeNameEnumApi | null
    inference: InferenceModeEnumApi | null
    idle_minutes: number | null
    output_schema: string
}

type RunDefaults = Pick<
    CloudAgentPresetApi | CloudAgentSettingsApi,
    'repositories' | 'model' | 'reasoning_effort' | 'size' | 'inference' | 'idle_minutes' | 'output_schema'
>

function prefill(defaults: RunDefaults | null, fallback: RunDefaults | null): Omit<NewRunForm, 'prompt' | 'preset'> {
    const repositories = defaults?.repositories ?? fallback?.repositories
    return {
        ...repositoryFields(repositories),
        model: defaults?.model ?? fallback?.model ?? null,
        reasoning_effort: defaults?.reasoning_effort ?? fallback?.reasoning_effort ?? null,
        size: defaults?.size ?? fallback?.size ?? null,
        inference: defaults?.inference ?? fallback?.inference ?? null,
        idle_minutes: defaults?.idle_minutes ?? fallback?.idle_minutes ?? null,
        output_schema: outputSchemaToText(defaults?.output_schema ?? fallback?.output_schema),
    }
}

function toRequest(form: NewRunForm): CloudAgentRunCreateApi {
    const repositories = toRepositories(form.repository, form.branch)
    const outputSchema = parseOutputSchema(form.output_schema).schema
    return {
        prompt: form.prompt.trim(),
        ...(repositories ? { repositories } : {}),
        ...(form.preset ? { preset: form.preset } : {}),
        ...(form.model ? { model: form.model } : {}),
        ...(form.reasoning_effort ? { reasoning_effort: form.reasoning_effort } : {}),
        ...(form.size ? { size: form.size } : {}),
        ...(form.inference ? { inference: form.inference } : {}),
        ...(form.idle_minutes !== null ? { idle_minutes: form.idle_minutes } : {}),
        ...(outputSchema ? { output_schema: outputSchema } : {}),
    }
}

