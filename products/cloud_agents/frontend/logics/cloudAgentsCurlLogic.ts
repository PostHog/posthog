import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import posthog from 'posthog-js'

import { apiHostOrigin } from 'lib/utils/apiHost'
import { projectLogic } from 'scenes/projectLogic'

import { getCloudAgentsRunsCreateUrl } from '../generated/api'
import type { CloudAgentRunCreateApi } from '../generated/api.schemas'

export type CurlSurface = 'empty_state' | 'preset'

/** The request that starts a run, as a curl command for the current project. */
export function buildRunCurl(runsUrl: string, body: CloudAgentRunCreateApi): string {
    return [
        `curl -X POST "${runsUrl}" \\`,
        `  -H "Authorization: Bearer $POSTHOG_PERSONAL_API_KEY" \\`,
        `  -H "Content-Type: application/json" \\`,
        `  -d '${JSON.stringify(body).replace(/'/g, "'\\''")}'`,
    ].join('\n')
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface cloudAgentsCurlLogicValues {
    currentProjectId: number | null // projectLogic
    runsUrl: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface cloudAgentsCurlLogicActions {
    reportCurlCopied: (surface: CurlSurface) => {
        surface: CurlSurface
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface cloudAgentsCurlLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        runsUrl: (currentProjectId: number | null) => string
    }
}

export type cloudAgentsCurlLogicType = MakeLogicType<
    cloudAgentsCurlLogicValues,
    cloudAgentsCurlLogicActions,
    Record<string, any>,
    cloudAgentsCurlLogicMeta
>

export const cloudAgentsCurlLogic = kea<cloudAgentsCurlLogicType>([
    path(['products', 'cloud_agents', 'frontend', 'logics', 'cloudAgentsCurlLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        reportCurlCopied: (surface: CurlSurface) => ({ surface }),
    }),
    selectors({
        runsUrl: [
            (s) => [s.currentProjectId],
            (projectId: number | null): string => `${apiHostOrigin()}${getCloudAgentsRunsCreateUrl(String(projectId))}`,
        ],
    }),
    listeners({
        reportCurlCopied: ({ surface }) => {
            // pinned: analytics event and property names. A rename breaks the dashboards that read them.
            posthog.capture('cloud_agents_curl_copied', { surface })
        },
    }),
])
