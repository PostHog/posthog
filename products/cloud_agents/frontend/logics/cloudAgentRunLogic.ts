export type cloudAgentRunLogicType = MakeLogicType<
    cloudAgentRunLogicValues,
    cloudAgentRunLogicActions,
    CloudAgentRunLogicProps,
    cloudAgentRunLogicMeta
>

export const cloudAgentRunLogic = kea<cloudAgentRunLogicType>([
    props({} as CloudAgentRunLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'cloud_agents', 'frontend', 'logics', 'cloudAgentRunLogic', key]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        pollRun: true,
        setRun: (run: CloudAgentRunApi) => ({ run }),
        cancelRun: true,
        cancelRunDone: (error: string | null) => ({ error }),
        setFollowupText: (text: string) => ({ text }),
        sendFollowup: true,
        sendFollowupDone: (error: string | null) => ({ error }),
        showEarlierEvents: true,
    }),
    loaders(({ props, values }) => ({
        run: [
            null as CloudAgentRunApi | null,
            {
                loadRun: async (): Promise<CloudAgentRunApi> =>
                    await cloudAgentsRunsRetrieve(String(values.currentProjectId), props.id),
                setRun: ({ run }) => run,
            },
        ],
        runEvents: [
            null as CloudAgentRunEventsApi | null,
            {
                loadRunEvents: async (): Promise<CloudAgentRunEventsApi> => {
                    const response = await cloudAgentsRunsEventsRetrieve(String(values.currentProjectId), props.id, {
                        format: 'json',
                    })
                    // The same URL can answer with an event stream as text. Only the JSON form has events to show.
                    return typeof response === 'string' ? EMPTY_EVENTS : response
                },
            },
        ],
    })),
    reducers({
        runLoadError: [
            null as RunLoadError | null,
            {
                loadRunSuccess: () => null,
                loadRunFailure: (_, { errorObject }) => (errorObject?.status === 404 ? 'not_found' : 'failed'),
            },
        ],
        runEventsLoadFailed: [false, { loadRunEventsSuccess: () => false, loadRunEventsFailure: () => true }],
        cancelling: [false, { cancelRun: () => true, cancelRunDone: () => false }],
        cancelError: [null as string | null, { cancelRun: () => null, cancelRunDone: (_, { error }) => error }],
        followupText: [
            '',
            {
                setFollowupText: (_, { text }) => text,
                sendFollowupDone: (state, { error }) => (error ? state : ''),
            },
        ],
        followupSending: [false, { sendFollowup: () => true, sendFollowupDone: () => false }],
        followupError: [null as string | null, { sendFollowup: () => null, sendFollowupDone: (_, { error }) => error }],
        timelineLimit: [TIMELINE_PAGE_SIZE as number, { showEarlierEvents: (state) => state + TIMELINE_PAGE_SIZE }],
    }),
    selectors({
        isActive: [(s) => [s.run], (run: CloudAgentRunApi | null): boolean => !!run && isRunActive(run.status)],
        isDone: [(s) => [s.run], (run: CloudAgentRunApi | null): boolean => !!run && isRunDone(run.status)],
        timelineRows: [
            (s) => [s.runEvents],
            (runEvents: CloudAgentRunEventsApi | null): TimelineRow[] =>
                runEvents ? buildTimeline(runEvents.events) : [],
        ],
        visibleTimelineRows: [
            (s) => [s.timelineRows, s.timelineLimit],
            (rows: TimelineRow[], limit: 100): TimelineRow[] =>
                rows.length > limit ? rows.slice(rows.length - limit) : rows,
        ],
        hiddenTimelineRowCount: [
            (s) => [s.timelineRows, s.timelineLimit],
            (rows: TimelineRow[], limit: 100): number => Math.max(rows.length - limit, 0),
        ],
        eventsTruncated: [
            (s) => [s.runEvents],
            (runEvents: CloudAgentRunEventsApi | null): boolean => !!runEvents?.truncated,
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        const schedulePoll = (): void => {
            if (!values.isActive) {
                cache.disposables.dispose('poll')
                return
            }
            cache.disposables.add(() => {
                const timer = window.setTimeout(() => actions.pollRun(), RUN_POLL_INTERVAL_MS)
                return () => window.clearTimeout(timer)
            }, 'poll')
        }
        return {
            pollRun: () => {
                actions.loadRun()
                actions.loadRunEvents()
            },
            loadRunEventsSuccess: schedulePoll,
            // A run that is still active must keep its poll after one failed event read.
            loadRunEventsFailure: schedulePoll,
            setRunSuccess: () => {
                actions.loadRunEvents()
            },
            cancelRun: async () => {
                // pinned: analytics event name. A rename breaks the dashboards that read it.
                posthog.capture('cloud_agents_cancel_clicked')
                try {
                    const run = await cloudAgentsRunsCancelCreate(String(values.currentProjectId), props.id)
                    actions.setRun(run)
                    actions.cancelRunDone(null)
                } catch (error) {
                    actions.cancelRunDone(
                        describeRunError(error, 'Could not cancel the run. Refresh the page and try again.')
                    )
                }
            },
            sendFollowup: async () => {
                const content = values.followupText.trim()
                if (!content) {
                    actions.sendFollowupDone('Write a message for the agent first.')
                    return
                }
                // pinned: analytics event name. A rename breaks the dashboards that read it.
                posthog.capture('cloud_agents_followup_submitted')
                try {
                    const response = await cloudAgentsRunsMessagesCreate(String(values.currentProjectId), props.id, {
                        content,
                    })
                    actions.setRun(response.run)
                    actions.sendFollowupDone(null)
                } catch (error) {
                    actions.sendFollowupDone(
                        describeRunError(error, 'Could not send the message. Try again in a moment.')
                    )
                    // The run finished for good while the page showed it as idle, so show it as done.
                    if ((error as { code?: string | null }).code === 'run_done') {
                        actions.loadRun()
                    }
                }
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadRun()
        actions.loadRunEvents()
    }),
])
