export type cloudAgentsSettingsLogicType = MakeLogicType<
    cloudAgentsSettingsLogicValues,
    cloudAgentsSettingsLogicActions
>

export const cloudAgentsSettingsLogic = kea<cloudAgentsSettingsLogicType>([
    path(['products', 'cloud_agents', 'frontend', 'logics', 'cloudAgentsSettingsLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    loaders(({ values }) => ({
        settings: [
            null as CloudAgentSettingsApi | null,
            {
                loadSettings: async (): Promise<CloudAgentSettingsApi> =>
                    await cloudAgentsSettingsRetrieve(String(values.currentProjectId)),
            },
        ],
    })),
    reducers({
        settingsLoadFailed: [false, { loadSettings: () => false, loadSettingsFailure: () => true }],
    }),
    forms(({ actions, values }) => ({
        teamDefaults: {
            defaults: EMPTY_TEAM_DEFAULTS,
            errors: ({ repository, idle_minutes, output_schema }) => ({
                repository: validateRepository(repository),
                idle_minutes: validateIdleMinutes(idle_minutes),
                output_schema: validateOutputSchema(output_schema),
            }),
            submit: async (form) => {
                try {
                    const settings = await cloudAgentsSettingsPartialUpdate(
                        String(values.currentProjectId),
                        toPatch(form)
                    )
                    actions.loadSettingsSuccess(settings)
                    // pinned: analytics event name. A rename breaks the dashboards that read it.
                    posthog.capture('cloud_agents_settings_saved')
                    lemonToast.success('Saved the team defaults')
                } catch (error) {
                    const detail = (error as { detail?: string | null }).detail
                    lemonToast.error(detail || 'Could not save the team defaults. Try again.')
                    throw error
                }
            },
        },
    })),
    listeners(({ actions, values }) => ({
        loadSettingsSuccess: ({ settings }) => {
            if (settings && !values.teamDefaultsChanged) {
                actions.resetTeamDefaults(toForm(settings))
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSettings()
    }),
])
