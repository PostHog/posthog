/** The stored Claude subscription of the signed-in user. Each person connects their own. */
export const claudeSubscriptionLogic = kea<claudeSubscriptionLogicType>([
    path(['products', 'cloud_agents', 'frontend', 'logics', 'claudeSubscriptionLogic']),
    actions({
        openConnectModal: true,
        closeConnectModal: true,
        setToken: (token: string) => ({ token }),
        submitToken: true,
        setConnectError: (connectError: string | null) => ({ connectError }),
    }),
    loaders(({ values }) => ({
        claudeSubscription: [
            null as UserClaudeSubscriptionApi | null,
            {
                loadClaudeSubscription: async () => await usersIntegrationsClaudeSubscriptionRetrieve(CURRENT_USER),
                connectClaudeSubscription: async () =>
                    await usersIntegrationsClaudeSubscriptionCreate(CURRENT_USER, { token: values.token.trim() }),
                disconnectClaudeSubscription: async (): Promise<UserClaudeSubscriptionApi> => {
                    await usersIntegrationsClaudeSubscriptionDestroy(CURRENT_USER)
                    return NOT_CONNECTED
                },
            },
        ],
    })),
    reducers({
        connectModalOpen: [
            false,
            {
                openConnectModal: () => true,
                closeConnectModal: () => false,
                connectClaudeSubscriptionSuccess: () => false,
            },
        ],
        token: [
            '',
            {
                setToken: (_, { token }) => token,
                openConnectModal: () => '',
                closeConnectModal: () => '',
                connectClaudeSubscriptionSuccess: () => '',
            },
        ],
        connectError: [
            null as string | null,
            {
                setConnectError: (_, { connectError }) => connectError,
                setToken: () => null,
                openConnectModal: () => null,
                connectClaudeSubscription: () => null,
            },
        ],
        connecting: [
            false,
            {
                connectClaudeSubscription: () => true,
                connectClaudeSubscriptionSuccess: () => false,
                connectClaudeSubscriptionFailure: () => false,
            },
        ],
        claudeSubscriptionLoadFailed: [
            false,
            {
                loadClaudeSubscription: () => false,
                loadClaudeSubscriptionFailure: () => true,
            },
        ],
    }),
    selectors({
        connected: [
            (s) => [s.claudeSubscription],
            (claudeSubscription: UserClaudeSubscriptionApi | null): boolean =>
                claudeSubscription?.status === ClaudeSubscriptionStatusEnumApi.Connected,
        ],
    }),
    listeners(({ actions, values }) => ({
        openConnectModal: () => {
            // pinned: analytics event and property names. A rename breaks the dashboards that read them.
            posthog.capture('personal integration connect clicked', {
                integration_kind: 'claude_subscription',
                surface: 'cloud_agents',
            })
        },
        submitToken: () => {
            if (values.connecting) {
                return
            }
            if (!values.token.trim()) {
                actions.setConnectError('Paste the token first.')
                return
            }
            actions.connectClaudeSubscription()
        },
        connectClaudeSubscriptionSuccess: () => {
            lemonToast.success('Claude connected')
        },
        connectClaudeSubscriptionFailure: ({ errorObject }) => {
            actions.setConnectError(describeClaudeSubscriptionError(errorObject))
        },
        disconnectClaudeSubscriptionSuccess: () => {
            lemonToast.success('Claude disconnected')
        },
        disconnectClaudeSubscriptionFailure: () => {
            lemonToast.error('Could not disconnect Claude. Try again.')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadClaudeSubscription()
    }),
])
