export const cloudAgentPresetLogic = kea<cloudAgentPresetLogicType>([
    props({} as CloudAgentPresetLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'cloud_agents', 'frontend', 'logics', 'cloudAgentPresetLogic', key]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    loaders(({ props, values }) => ({
        preset: [
            null as CloudAgentPresetApi | null,
            {
                loadPreset: async (): Promise<CloudAgentPresetApi> =>
                    await cloudAgentsPresetsRetrieve(String(values.currentProjectId), props.id),
            },
        ],
    })),
    reducers({
        presetLoadError: [
            null as 'not_found' | 'failed' | null,
            {
                loadPresetSuccess: () => null,
                loadPresetFailure: (_, { errorObject }) => (errorObject?.status === 404 ? 'not_found' : 'failed'),
            },
        ],
    }),
    forms(({ actions, props, values }) => ({
        presetForm: {
            defaults: EMPTY_PRESET,
            errors: ({ name, repository, idle_minutes, output_schema }) => ({
                name: !name.trim() ? 'Give the preset a name' : undefined,
                repository: validateRepository(repository),
                idle_minutes: validateIdleMinutes(idle_minutes),
                output_schema: validateOutputSchema(output_schema),
            }),
            submit: async (form) => {
                const isNew = props.id === 'new'
                const projectId = String(values.currentProjectId)
                try {
                    if (isNew) {
                        await cloudAgentsPresetsCreate(projectId, toRequest(form))
                    } else {
                        await cloudAgentsPresetsPartialUpdate(projectId, props.id, toRequest(form))
                    }
                } catch (error) {
                    const { attr, detail } = error as { attr?: string | null; detail?: string | null }
                    const field = attr ? formFieldForApiAttr(attr) : null
                    if (field && field in form && detail) {
                        actions.setPresetFormManualErrors({ [field]: detail })
                    } else {
                        lemonToast.error(detail || 'Could not save the preset. Try again.')
                    }
                    throw error
                }
                // pinned: analytics event and property names. A rename breaks the dashboards that read them.
                posthog.capture('cloud_agents_preset_saved', { is_new: isNew })
                lemonToast.success(`Saved the preset "${form.name.trim()}"`)
                router.actions.push(urls.cloudAgentPresets())
            },
        },
    })),
    selectors({
        isNew: [() => [(_, props) => props.id], (id): boolean => id === 'new'],
    }),
    listeners(({ actions }) => ({
        loadPresetSuccess: ({ preset }) => {
            if (preset) {
                actions.resetPresetForm(toForm(preset))
            }
        },
    })),
    afterMount(({ actions, props }) => {
        if (props.id !== 'new') {
            actions.loadPreset()
        }
    }),
])
