class MarketingAnalyticsRecommendationsQueryRunner(
    AnalyticsQueryRunner[MarketingAnalyticsRecommendationsQueryResponse]
):
    query: MarketingAnalyticsRecommendationsQuery
    response: MarketingAnalyticsRecommendationsQueryResponse
    cached_response: CachedMarketingAnalyticsRecommendationsQueryResponse

    @cached_property
    def query_date_range(self) -> QueryDateRange:
        return QueryDateRange(date_range=self.query.dateRange, team=self.team, interval=None, now=datetime.now())

    @cached_property
    def hogql_database(self) -> Database:
        return Database.create_for(
            team=self.team,
            user=self.user,
            modifiers=create_default_modifiers_for_team(self.team, self.modifiers),
            timings=self.timings,
        )

    @cached_property
    def hogql_context(self) -> HogQLContext:
        return HogQLContext(
            team_id=self.team.pk,
            modifiers=create_default_modifiers_for_team(self.team, self.modifiers),
            database=self.hogql_database,
        )

    def to_query(self) -> ast.SelectQuery:
        return ast.SelectQuery(select=[ast.Constant(value=1)])

    def _calculate(self) -> MarketingAnalyticsRecommendationsQueryResponse:
        sources = self.query.sources if self.query.sources is not None else self._project_sources()
        if not sources:
            return MarketingAnalyticsRecommendationsQueryResponse(results=[], disclaimer=DISCLAIMER, dataGaps=[])
        ads = [source for source in sources if source.sourceType == "GoogleAds"]
        organic = [source for source in sources if source.sourceType == "GoogleSearchConsole"]
        date_from, date_to = self.query_date_range.date_from(), self.query_date_range.date_to()
        organic_queries = tuple(query for source in organic for query in self._organic_queries(source))
        site_urls = tuple(url for source in organic for url in self._site_urls(source))
        ranking_pages = tuple(page for source in organic for page in self._ranking_pages(source))
        days = max((date_to - date_from).days + 1, 1)
        results: list[MarketingAnalyticsRecommendation] = []
        data_gaps: list[MarketingAnalyticsRecommendationsDataGap] = []
        # Each ad account has its own campaigns, costs and currency, so rules compare a campaign only with
        # campaigns from the same account. Search Console data is shared because it has no account link.
        for source in ads:
            actions = self._account_conversion_actions(source)
            missing = self._missing_conversion_action_tables(source) if actions else []
            if missing:
                # Campaign and search term CPAs feed each other, so the account falls back as a whole.
                actions = None
            campaigns = tuple(self._campaigns(source, actions))
            has_performance_max = any(campaign.channel_type == "PERFORMANCE_MAX" for campaign in campaigns)
            data_gaps.extend(self._data_gaps(source, actions, missing, has_performance_max))
            results.extend(
                recommend(
                    RecommendationInputs(
                        campaigns=campaigns,
                        search_terms=tuple(self._search_terms(source, actions)),
                        organic_queries=organic_queries,
                        site_urls=site_urls,
                        currency=self._currency(source),
                        days=self._days_with_data(source) or days,
                        term_keywords=tuple(self._term_keywords(source)),
                        ranking_pages=ranking_pages,
                        keyword_tracking=self._keyword_tracking(source),
                        ads=tuple(self._ads(source)),
                    )
                )
            )
        return MarketingAnalyticsRecommendationsQueryResponse(
            results=_dedupe_organic_only(results), disclaimer=DISCLAIMER, dataGaps=data_gaps
        )

    def _project_sources(self) -> list[MarketingAnalyticsRecommendationsSource]:
        table_keys = all_queryable_table_keys(self.team.pk)
        sources = []
        for source in list_sources(self.team.pk):
            if source.source_type not in RECOMMENDATION_SOURCE_TYPES:
                continue
            tables = {
                schema.name: table_keys[schema.table_id].queryable_key
                for schema in list_schemas_for_source(source.id, self.team.pk)
                if schema.should_sync
                and schema.last_synced_at is not None
                and schema.table_id is not None
                and schema.table_id in table_keys
            }
            recommendation_source = _recommendation_source(source.source_type, tables)
            if recommendation_source is not None:
                sources.append(recommendation_source)
        return sources

    def _readable(self, table: str | None) -> bool:
        if not table:
            return False
        return self.hogql_database.has_table(table) and not self.hogql_database.is_table_access_denied(table)

    def _has_field(self, table: str, field: str) -> bool:
        return self.hogql_database.get_table(table.split(".")).has_field(field)

    def _field(self, table: str, field: str) -> ast.Expr:
        if self._has_field(table, field):
            return ast.Field(chain=[field])
        return ast.Constant(value=None)

    def _select(self, sql: str, table: str, **placeholders: ast.Expr) -> list[list[Any]]:
        date_range = self.query_date_range
        result = execute_hogql_query(
            query_type="marketing_analytics_recommendations_query",
            query=parse_select(
                # HogQL caps a query without a LIMIT at 100 rows, and accounts often have more campaigns.
                sql if "LIMIT" in sql else f"{sql}\nLIMIT {ROW_LIMIT}",
                placeholders={
                    "table": ast.Field(chain=list[str | int](table.split("."))),
                    "date_from": ast.Constant(value=date_range.date_from()),
                    "date_to": ast.Constant(value=date_range.date_to()),
                    **placeholders,
                },
            ),
            context=self.hogql_context,
            team=self.team,
            user=self.user,
            timings=self.timings,
            modifiers=self.modifiers,
            limit_context=self.limit_context,
        )
        return result.results or []

    def _campaigns(
        self, source: MarketingAnalyticsRecommendationsSource, actions: list[str] | None
    ) -> list[CampaignStats]:
        if not self._readable(source.campaignTable) or not self._readable(source.campaignStatsTable):
            return []
        assert source.campaignTable and source.campaignStatsTable
        definitions = {
            row[0]: row
            for row in self._select(
                """
                SELECT toString(campaign_id), any(campaign_name), any(campaign_advertising_channel_type),
                    any({primary_status}), any(toString({status_reasons})),
                    any(campaign_budget_amount_micros) / 1000000, any({recommended_budget}) / 1000000,
                    any(toString({budget_id})), any(toString({serving_status})), any({target_cpa}) / 1000000,
                    any(toString({tracking_url_template}))
                FROM {table} GROUP BY campaign_id
                """,
                source.campaignTable,
                primary_status=self._field(source.campaignTable, "campaign_primary_status"),
                status_reasons=self._field(source.campaignTable, "campaign_primary_status_reasons"),
                recommended_budget=self._field(
                    source.campaignTable, "campaign_budget_recommended_budget_amount_micros"
                ),
                budget_id=self._field(source.campaignTable, "campaign_campaign_budget"),
                serving_status=self._field(source.campaignTable, "campaign_status"),
                target_cpa=self._field(source.campaignTable, "campaign_target_cpa_target_cpa_micros"),
                tracking_url_template=self._field(source.campaignTable, "campaign_tracking_url_template"),
            )
        }
        spend = {
            row[0]: row
            for row in self._select(
                """
                SELECT toString(campaign_id), sum(toFloat(metrics_cost_micros)) / 1000000, sum(toFloat(metrics_conversions))
                FROM {table}
                WHERE toDate(segments_date) >= toDate({date_from}) AND toDate(segments_date) <= toDate({date_to})
                GROUP BY campaign_id
                """,
                source.campaignStatsTable,
            )
        }
        shares = self._impression_shares(source.campaignImpressionShareTable)
        selected = self._selected_campaign_conversions(source.campaignConversionActionTable, actions)
        performance_max_terms = self._readable(source.performanceMaxSearchTermTable)
        campaigns = []
        for campaign_id, (_, cost, conversions) in spend.items():
            definition = definitions.get(campaign_id)
            if not definition or not cost:
                continue
            # Performance Max search terms count primary actions, and its brand leak subtracts them from the campaign.
            if selected is not None and not (definition[2] == "PERFORMANCE_MAX" and performance_max_terms):
                conversions = selected.get(campaign_id, 0.0)
            share = shares.get(campaign_id, (None, None, None))
            campaigns.append(
                CampaignStats(
                    id=campaign_id,
                    name=definition[1] or campaign_id,
                    channel_type=definition[2],
                    # Older syncs lack primary_status, and campaign_status still tells paused and removed apart.
                    primary_status=definition[3] or definition[8] or None,
                    status_reasons=_parse_reasons(definition[4]),
                    daily_budget=definition[5],
                    recommended_daily_budget=definition[6] or None,
                    cost=float(cost),
                    conversions=float(conversions or 0),
                    impression_share=share[0],
                    lost_to_budget=share[1],
                    lost_to_rank=share[2],
                    budget_id=definition[7] or None,
                    # Google Ads bids to the target with primary actions, so it is no benchmark for selected ones.
                    target_cpa=(definition[9] or None) if selected is None else None,
                    tracking_url_template=definition[10] or None,
                )
            )
        return campaigns

    @cached_property
    def _google_ads_sessions(self) -> GoogleAdsSessions:
        # gclid is the one parameter every auto-tagged Google Ads click carries, so it finds paid sessions without
        # relying on the UTMs this rule checks. It cannot tell ad accounts apart, so every account shares the count.
        rows = self._select(
            """
            SELECT count(), countIf(notEmpty(coalesce($entry_utm_term, '')))
            FROM {table}
            WHERE $start_timestamp >= {date_from} AND $start_timestamp <= {date_to}
                AND notEmpty(coalesce($entry_gclid, ''))
            """,
            "sessions",
        )
        if not rows:
            return GoogleAdsSessions(total=0, with_keyword=0)
        return GoogleAdsSessions(total=int(rows[0][0] or 0), with_keyword=int(rows[0][1] or 0))

    def _keyword_tracking(self, source: MarketingAnalyticsRecommendationsSource) -> KeywordTracking | None:
        sessions = self._google_ads_sessions
        if not sessions.total:
            return None
        name, template, suffix = None, None, None
        table = source.customerTable
        if self._readable(table):
            assert table
            rows = self._select(
                "SELECT any(toString({name})), any(toString({template})), any(toString({suffix})) FROM {table}",
                table,
                name=self._field(table, "customer_descriptive_name"),
                template=self._field(table, "customer_tracking_url_template"),
                suffix=self._field(table, "customer_final_url_suffix"),
            )
            if rows:
                name, template, suffix = rows[0]
        return KeywordTracking(
            account_name=name or self._account_label(source),
            sessions=sessions.total,
            sessions_with_keyword=sessions.with_keyword,
            account_tracking_url_template=template or None,
            account_final_url_suffix=suffix or None,
        )

    def _account_label(self, source: MarketingAnalyticsRecommendationsSource) -> str:
        customer_id = self._customer_id(source)
        if customer_id and len(customer_id) == 10:
            customer_id = f"{customer_id[:3]}-{customer_id[3:6]}-{customer_id[6:]}"
        return f"Google Ads account {customer_id}" if customer_id else "Google Ads account"

    def _impression_shares(self, table: str | None) -> dict[str, tuple[float | None, ...]]:
        if not table or not self._readable(table):
            return {}
        fields = {
            name: self._field(table, f"metrics_search_{name}")
            for name in (
                "impression_share",
                "budget_lost_impression_share",
                "rank_lost_impression_share",
            )
        }
        rows = self._select(
            """
            SELECT toString(campaign_id),
                sumIf(toFloat({impression_share}) * metrics_impressions, {impression_share} IS NOT NULL)
                    / nullIf(sumIf(metrics_impressions, {impression_share} IS NOT NULL), 0),
                sumIf(toFloat({budget_lost_impression_share}) * metrics_impressions, {budget_lost_impression_share} IS NOT NULL)
                    / nullIf(sumIf(metrics_impressions, {budget_lost_impression_share} IS NOT NULL), 0),
                sumIf(toFloat({rank_lost_impression_share}) * metrics_impressions, {rank_lost_impression_share} IS NOT NULL)
                    / nullIf(sumIf(metrics_impressions, {rank_lost_impression_share} IS NOT NULL), 0)
            FROM {table}
            WHERE toDate(segments_date) >= toDate({date_from}) AND toDate(segments_date) <= toDate({date_to})
            GROUP BY campaign_id
            """,
            table,
            **fields,
        )
        return {row[0]: tuple(row[1:]) for row in rows}

    def _account_conversion_actions(self, source: MarketingAnalyticsRecommendationsSource) -> list[str] | None:
        actions = self.query.conversionActions
        if not actions:
            return None
        customer_id = self._customer_id(source)
        if customer_id is None:
            return list(actions)
        # Resource names carry the customer ID, so another account's actions would zero this account's conversions.
        # Actions shared from a manager account carry the manager's ID, so the account's own split rows count too.
        reported = self._reported_conversion_actions(source.campaignConversionActionTable, actions)
        own = [action for action in actions if action.startswith(f"customers/{customer_id}/") or action in reported]
        return own or None

    def _reported_conversion_actions(self, table: str | None, actions: list[str]) -> set[str]:
        if not self._readable(table):
            return set()
        assert table
        rows = self._select(
            "SELECT DISTINCT segments_conversion_action FROM {table} WHERE has({actions}, segments_conversion_action)",
            table,
            actions=ast.Constant(value=actions),
        )
        return {row[0] for row in rows}

    def _customer_id(self, source: MarketingAnalyticsRecommendationsSource) -> str | None:
        table = source.campaignTable
        if not self._readable(table):
            return None
        assert table
        if not self._has_field(table, "customer_id"):
            return None
        rows = self._select("SELECT any(toString(customer_id)) FROM {table}", table)
        return rows[0][0] if rows and rows[0][0] else None

    def _missing_conversion_action_tables(self, source: MarketingAnalyticsRecommendationsSource) -> list[str]:
        missing = []
        if not self._readable(source.campaignConversionActionTable):
            missing.append("campaign_conversion_action_stats")
        if self._readable(source.searchTermTable) and not self._readable(source.searchTermConversionActionTable):
            missing.append("search_term_conversion_action_stats")
        return missing

    def _data_gaps(
        self,
        source: MarketingAnalyticsRecommendationsSource,
        actions: list[str] | None,
        missing: list[str],
        has_performance_max: bool,
    ) -> list[MarketingAnalyticsRecommendationsDataGap]:
        if missing:
            tables = " and ".join(missing)
            verb, pronoun = ("is", "it") if len(missing) == 1 else ("are", "them")
            message = (
                f"CPAs count the primary conversion actions, because {tables} {verb} not synced. "
                f"Sync {pronoun} to count only the selected conversion actions."
            )
            kind = MarketingAnalyticsRecommendationsDataGapKind.CONVERSION_ACTION_TABLES_NOT_SYNCED
        elif actions and has_performance_max and self._readable(source.performanceMaxSearchTermTable):
            message = PERFORMANCE_MAX_GAP
            kind = MarketingAnalyticsRecommendationsDataGapKind.PERFORMANCE_MAX_SEARCH_TERMS_COUNT_PRIMARY_CONVERSIONS
        else:
            return []
        return [
            MarketingAnalyticsRecommendationsDataGap(kind=kind, campaignTable=source.campaignTable, message=message)
        ]

    def _selected_campaign_conversions(self, table: str | None, actions: list[str] | None) -> dict[str, float] | None:
        if not actions or not table:
            return None
        # metrics_conversions counts primary actions only, so a selected secondary action is read from all_conversions.
        rows = self._select(
            """
            SELECT toString(campaign_id), sum(toFloat(metrics_all_conversions))
            FROM {table}
            WHERE toDate(segments_date) >= toDate({date_from}) AND toDate(segments_date) <= toDate({date_to})
                AND has({actions}, segments_conversion_action)
            GROUP BY campaign_id
            """,
            table,
            actions=ast.Constant(value=actions),
        )
        return {row[0]: float(row[1] or 0) for row in rows}

    def _search_terms(
        self, source: MarketingAnalyticsRecommendationsSource, actions: list[str] | None
    ) -> list[SearchTermStats]:
        terms: list[SearchTermStats] = []
        for table, term_field, status_field, split_table in (
            (
                source.searchTermTable,
                "search_term_view_search_term",
                "search_term_view_status",
                source.searchTermConversionActionTable,
            ),
            (source.performanceMaxSearchTermTable, "campaign_search_term_view_search_term", None, None),
        ):
            if not table or not self._readable(table):
                continue
            # Joined in the same query, so the row limit keeps each term's selected conversions with its cost.
            selected_join = (
                """
                LEFT JOIN (
                    SELECT lower(trim(search_term_view_search_term)) AS split_term, toString(campaign_id) AS split_campaign,
                        sum(toFloat(metrics_all_conversions)) AS split_conversions
                    FROM {split_table}
                    WHERE toDate(segments_date) >= toDate({date_from}) AND toDate(segments_date) <= toDate({date_to})
                        AND has({actions}, segments_conversion_action)
                    GROUP BY split_term, split_campaign
                ) AS selected
                ON selected.split_term = lower(trim({term})) AND selected.split_campaign = toString(campaign_id)
                """
                if actions and split_table
                else ""
            )
            conversions = (
                "coalesce(any(selected.split_conversions), 0)" if selected_join else "sum(toFloat(metrics_conversions))"
            )
            # Performance Max search terms have no ad groups.
            ad_groups = "groupUniqArray(toString(ad_group_id))" if self._has_field(table, "ad_group_id") else "NULL"
            rows = self._select(
                f"""
                SELECT lower(trim({{term}})) AS term, toString(campaign_id), sum(metrics_clicks), sum(metrics_impressions),
                    sum(toFloat(metrics_cost_micros)) / 1000000, {conversions}, any(toString({{status}})),
                    sumIf(toFloat({{absolute_top}}) * metrics_impressions, {{absolute_top}} IS NOT NULL)
                        / nullIf(sumIf(metrics_impressions, {{absolute_top}} IS NOT NULL), 0),
                    {ad_groups}
                FROM {{table}}
                {selected_join}
                WHERE toDate(segments_date) >= toDate({{date_from}}) AND toDate(segments_date) <= toDate({{date_to}})
                    AND notEmpty(term)
                GROUP BY term, campaign_id
                ORDER BY sum(metrics_cost_micros) DESC
                LIMIT {ROW_LIMIT}
                """,
                table,
                term=ast.Field(chain=[term_field]),
                status=ast.Field(chain=[status_field]) if status_field else ast.Constant(value="NONE"),
                absolute_top=self._field(table, "metrics_absolute_top_impression_percentage"),
                **(
                    {
                        "split_table": ast.Field(chain=list[str | int](split_table.split("."))),
                        "actions": ast.Constant(value=actions),
                    }
                    if actions and split_table
                    else {}
                ),
            )
            terms.extend(
                SearchTermStats(
                    term=row[0],
                    campaign_id=row[1],
                    clicks=float(row[2] or 0),
                    impressions=float(row[3] or 0),
                    cost=float(row[4] or 0),
                    conversions=float(row[5] or 0),
                    status=row[6] or "NONE",
                    absolute_top_percentage=row[7],
                    ad_group_ids=tuple(row[8] or ()),
                )
                for row in rows
            )
        return terms

    def _term_keywords(self, source: MarketingAnalyticsRecommendationsSource) -> list[TermKeywordStats]:
        if not source.searchTermKeywordTable or not self._readable(source.searchTermKeywordTable):
            return []
        rows = self._select(
            f"""
            SELECT lower(trim(search_term_view_search_term)) AS term, segments_keyword_info_text,
                toString(segments_keyword_info_match_type), sum(toFloat(metrics_cost_micros)) / 1000000 AS cost
            FROM {{table}}
            WHERE toDate(segments_date) >= toDate({{date_from}}) AND toDate(segments_date) <= toDate({{date_to}})
                AND notEmpty(term)
            GROUP BY term, segments_keyword_info_text, segments_keyword_info_match_type
            ORDER BY cost DESC
            LIMIT {ROW_LIMIT}
            """,
            source.searchTermKeywordTable,
        )
        return [
            TermKeywordStats(term=row[0], keyword=row[1] or "", match_type=row[2] or "", cost=float(row[3] or 0))
            for row in rows
            if row[1]
        ]

    def _ads(self, source: MarketingAnalyticsRecommendationsSource) -> list[Ad]:
        if not source.adTable or not self._readable(source.adTable):
            return []
        rows = self._select(
            """
            SELECT toString(ad_group_id), {headlines}, {descriptions}, {plain}
            FROM {table}
            WHERE ad_group_ad_status = 'ENABLED'
            """,
            source.adTable,
            headlines=self._field(source.adTable, "ad_group_ad_ad_responsive_search_ad_headlines"),
            descriptions=self._field(source.adTable, "ad_group_ad_ad_responsive_search_ad_descriptions"),
            # Expanded text ads still serve next to responsive ones, so their text is part of the ad group's copy too.
            plain=ast.Array(exprs=[self._field(source.adTable, field) for field in PLAIN_AD_TEXT_FIELDS]),
        )
        return [
            Ad(
                ad_group_id=row[0],
                texts=(*_asset_texts(row[1]), *_asset_texts(row[2]), *(text for text in row[3] if text)),
            )
            for row in rows
            if row[0]
        ]

    def _organic_queries(self, source: MarketingAnalyticsRecommendationsSource) -> list[OrganicQueryStats]:
        if not source.queryTable or not self._readable(source.queryTable):
            return []
        rows = self._select(
            f"""
            SELECT lower(trim(query)) AS q, sum(clicks), sum(impressions),
                sum(position * impressions) / nullIf(sum(impressions), 0)
            FROM {{table}}
            WHERE toDate(date) >= toDate({{date_from}}) AND toDate(date) <= toDate({{date_to}}) AND notEmpty(q)
            GROUP BY q
            ORDER BY sum(impressions) DESC
            LIMIT {ROW_LIMIT}
            """,
            source.queryTable,
        )
        return [
            OrganicQueryStats(
                query=row[0], clicks=float(row[1] or 0), impressions=float(row[2] or 0), position=float(row[3] or 0)
            )
            for row in rows
            if row[2]
        ]

    def _ranking_pages(self, source: MarketingAnalyticsRecommendationsSource) -> list[RankingPage]:
        if not source.queryPageTable or not self._readable(source.queryPageTable):
            return []
        rows = self._select(
            f"""
            SELECT q, argMax(page, page_impressions), max(page_impressions)
            FROM (
                SELECT lower(trim(query)) AS q, page, sum(impressions) AS page_impressions
                FROM {{table}}
                WHERE toDate(date) >= toDate({{date_from}}) AND toDate(date) <= toDate({{date_to}})
                    AND notEmpty(q) AND notEmpty(page)
                GROUP BY q, page
            )
            GROUP BY q
            ORDER BY max(page_impressions) DESC
            LIMIT {ROW_LIMIT}
            """,
            source.queryPageTable,
        )
        return [RankingPage(query=row[0], page=row[1], impressions=float(row[2] or 0)) for row in rows]

    def _site_urls(self, source: MarketingAnalyticsRecommendationsSource) -> list[str]:
        if not source.sitesTable or not self._readable(source.sitesTable):
            return []
        return [row[0] for row in self._select("SELECT site_url FROM {table} LIMIT 10", source.sitesTable) if row[0]]

    def _days_with_data(self, source: MarketingAnalyticsRecommendationsSource) -> int | None:
        # A source that started syncing inside the range has fewer days of spend, and monthly figures must use them.
        if not source.campaignStatsTable or not self._readable(source.campaignStatsTable):
            return None
        rows = self._select(
            """
            SELECT count(DISTINCT toDate(segments_date)) FROM {table}
            WHERE toDate(segments_date) >= toDate({date_from}) AND toDate(segments_date) <= toDate({date_to})
            """,
            source.campaignStatsTable,
        )
        return int(rows[0][0]) if rows and rows[0][0] else None

    def _currency(self, source: MarketingAnalyticsRecommendationsSource) -> str | None:
        # campaign_stats carries the account currency like the other marketing queries read it; the customer
        # table is only a fallback for stats synced before that column existed.
        for table in (source.campaignStatsTable, source.customerTable):
            if not table or not self._readable(table) or not self._has_field(table, "customer_currency_code"):
                continue
            rows = self._select(
                "SELECT anyIf(upper(customer_currency_code), length(coalesce(customer_currency_code, '')) > 0) FROM {table}",
                table,
            )
            if rows and rows[0][0]:
                return rows[0][0]
        return None


def _recommendation_source(source_type: str, tables: dict[str, str]) -> MarketingAnalyticsRecommendationsSource | None:
    if source_type == "GoogleAds":
        if "campaign" not in tables or "campaign_stats" not in tables:
            return None
        return MarketingAnalyticsRecommendationsSource(
            sourceType=MarketingAnalyticsRecommendationsSourceType.GOOGLE_ADS,
            campaignTable=tables["campaign"],
            campaignStatsTable=tables["campaign_stats"],
            campaignImpressionShareTable=tables.get("campaign_impression_share_stats"),
            customerTable=tables.get("customer"),
            searchTermTable=tables.get("search_term_stats"),
            searchTermKeywordTable=tables.get("search_term_keyword_stats"),
            adTable=tables.get("ad"),
            performanceMaxSearchTermTable=tables.get("performance_max_search_term_stats"),
            campaignConversionActionTable=tables.get("campaign_conversion_action_stats"),
            searchTermConversionActionTable=tables.get("search_term_conversion_action_stats"),
        )
    query_table = tables.get("search_analytics_by_query") or tables.get("search_analytics_by_query_page")
    if query_table is None:
        return None
    return MarketingAnalyticsRecommendationsSource(
        sourceType=MarketingAnalyticsRecommendationsSourceType.GOOGLE_SEARCH_CONSOLE,
        queryTable=query_table,
        queryPageTable=tables.get("search_analytics_by_query_page"),
        sitesTable=tables.get("sites"),
    )


def _asset_texts(value: str | None) -> tuple[str, ...]:
    # The sync stores each ad text asset as a JSON message inside a JSON list.
    try:
        assets = json.loads(value) if value else []
        parsed = [json.loads(asset) if isinstance(asset, str) else asset for asset in assets]
    except (ValueError, TypeError):
        return ()
    return tuple(text for asset in parsed if isinstance(asset, dict) and (text := asset.get("text")))


def _parse_reasons(value: str | None) -> tuple[str, ...]:
    if not value:
        return ()
    try:
        parsed = json.loads(value)
    except ValueError:
        return tuple(part.strip(" '\"") for part in value.strip("[]").split(",") if part.strip(" '\""))
    return tuple(str(reason) for reason in parsed) if isinstance(parsed, list) else ()


def _dedupe_organic_only(results: list[MarketingAnalyticsRecommendation]) -> list[MarketingAnalyticsRecommendation]:
    # Keyword gap reads only the shared Search Console data, so each ad account would repeat the same query.
    seen: set[str] = set()
    deduped = []
    for recommendation in results:
        if recommendation.rule == MarketingAnalyticsRecommendationRule.KEYWORD_GAP:
            if recommendation.subject in seen:
                continue
            seen.add(recommendation.subject)
        deduped.append(recommendation)
    return deduped
