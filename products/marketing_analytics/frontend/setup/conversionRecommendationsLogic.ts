export const conversionRecommendationsLogic: LogicWrapper<conversionRecommendationsLogicType> =
    kea<conversionRecommendationsLogicType>([
        props({} as ConversionRecommendationsProps),
        key(({ projectId, enabled, userId }) => `${userId}:${projectId}:${enabled}`),
        path((key) => ['products', 'marketing_analytics', 'setup', 'conversionRecommendationsLogic', key]),
        connect(({ projectId }: ConversionRecommendationsProps) => ({
            values: [conversionGoalFormLogic({ projectId }), ['findExistingGoal']],
        })),
        actions({
            requestAnalysis: (refresh: boolean) => ({ refresh }),
            dismissRecommendation: (recommendation: ConversionRecommendationApi) => ({ recommendation }),
            restoreRecommendation: (sourceRef: string) => ({ sourceRef }),
            syncPolling: true,
            setScanClock: (now: number) => ({ now }),
        }),
        loaders(({ props }) => ({
            state: [
                null as ConversionRecommendationStateApi | null,
                {
                    loadRecommendations: async (_: void, breakpoint) => {
                        const state = await api.marketingAnalyticsConversionRecommendationsRetrieve(
                            String(props.projectId)
                        )
                        breakpoint()
                        return state
                    },
                    startAnalysis: async ({ refresh }: { refresh: boolean }, breakpoint) => {
                        const state = await api.marketingAnalyticsConversionRecommendationsStartCreate(
                            String(props.projectId),
                            { refresh }
                        )
                        breakpoint()
                        return state
                    },
                },
            ],
        })),
        reducers(({ props }) => ({
            dismissedRecommendations: [
                {} as Record<string, DismissedRecommendation>,
                { persist: true, prefix: `${props.userId}:${props.projectId}__` },
                {
                    dismissRecommendation: (state, { recommendation }) => ({
                        ...state,
                        [recommendation.source_ref]: {
                            source_ref: recommendation.source_ref,
                            name: recommendation.name,
                        },
                    }),
                    restoreRecommendation: (state, { sourceRef }) => {
                        const next = { ...state }
                        delete next[sourceRef]
                        return next
                    },
                },
            ],
            scanClock: [
                Date.now(),
                {
                    setScanClock: (_, { now }) => now,
                    loadRecommendationsSuccess: () => Date.now(),
                    startAnalysisSuccess: () => Date.now(),
                },
            ],
            error: [
                null as string | null,
                {
                    loadRecommendationsSuccess: () => null,
                    startAnalysisSuccess: () => null,
                    loadRecommendationsFailure: () =>
                        'Could not load recommendations. Retry loading to check the latest results.',
                    startAnalysisFailure: () =>
                        'Could not confirm the analysis started. Reload its status before trying again.',
                },
            ],
        })),
        selectors({
            scanCooldownRemaining: [
                (s) => [s.state, s.scanClock],
                (state: ConversionRecommendationStateApi | null, scanClock: number): number => {
                    if (state?.latest_run?.status !== 'completed') {
                        return 0
                    }
                    const availableAt =
                        dayjs(state.latest_run.completed_at ?? state.latest_run.created_at).valueOf() + SCAN_COOLDOWN_MS
                    return Math.max(0, Math.ceil((availableAt - scanClock) / 60_000))
                },
            ],
            scanDisabledReason: [
                (s) => [s.state, s.scanCooldownRemaining],
                (state: ConversionRecommendationStateApi | null, scanCooldownRemaining: number): string | null => {
                    if (!state?.can_generate) {
                        return state?.generation_disabled_reason ?? 'Project admin access is required to scan events.'
                    }
                    return scanCooldownRemaining > 0
                        ? `You can scan again in ${scanCooldownRemaining} ${scanCooldownRemaining === 1 ? 'minute' : 'minutes'}.`
                        : null
                },
            ],
            unconfiguredRecommendations: [
                (s) => [s.state, s.findExistingGoal],
                (
                    state: ConversionRecommendationStateApi | null,
                    findExistingGoal: (recommendation: ConversionRecommendationApi) => ConversionGoalFilter | undefined
                ): ConversionRecommendationApi[] =>
                    (state?.results.recommendations ?? []).filter(
                        (recommendation) => !findExistingGoal(recommendation)
                    ),
            ],
            pendingRecommendations: [
                (s) => [s.unconfiguredRecommendations, s.dismissedRecommendations],
                (
                    recommendations: ConversionRecommendationApi[],
                    dismissed: Record<string, DismissedRecommendation>
                ): ConversionRecommendationApi[] =>
                    recommendations.filter((recommendation) => !dismissed[recommendation.source_ref]),
            ],
            dismissedRecommendationEntries: [
                (s) => [s.dismissedRecommendations],
                (dismissed: Record<string, DismissedRecommendation>): DismissedRecommendation[] =>
                    Object.values(dismissed),
            ],
            allRecommendationsHandled: [
                (s) => [s.state, s.pendingRecommendations],
                (state: ConversionRecommendationStateApi | null, pending: ConversionRecommendationApi[]): boolean =>
                    !!state?.result_run && pending.length === 0,
            ],
            allRecommendationsConfigured: [
                (s) => [s.state, s.unconfiguredRecommendations],
                (
                    state: ConversionRecommendationStateApi | null,
                    pendingRecommendations: ConversionRecommendationApi[]
                ): boolean =>
                    !!state?.result_run &&
                    !!state.results.recommendations?.length &&
                    pendingRecommendations.length === 0,
            ],
            isAnalyzing: [
                (s) => [s.state],
                (state: ConversionRecommendationStateApi | null): boolean =>
                    state?.latest_run?.status === 'pending' || state?.latest_run?.status === 'running',
            ],
        }),
        listeners(({ actions, values, cache, props }) => ({
            requestAnalysis: ({ refresh }) => {
                actions.setScanClock(Date.now())
                if (props.enabled && !values.scanDisabledReason && !values.stateLoading && !values.isAnalyzing) {
                    actions.startAnalysis({ refresh })
                }
            },
            loadRecommendationsSuccess: ({ state }) => {
                if (!state.latest_run && state.can_generate && !cache.initialAttempted) {
                    cache.initialAttempted = true
                    actions.requestAnalysis(false)
                }
                actions.syncPolling()
            },
            startAnalysisSuccess: () => actions.syncPolling(),
            loadRecommendationsFailure: () => cache.disposables.dispose('analysisPoll'),
            startAnalysisFailure: () => cache.disposables.dispose('analysisPoll'),
            syncPolling: () => {
                cache.disposables.dispose('analysisPoll')
                if (values.isAnalyzing) {
                    cache.disposables.add(() => {
                        const timer = setInterval(() => {
                            if (!values.stateLoading) {
                                actions.loadRecommendations()
                            }
                        }, POLL_INTERVAL_MS)
                        return () => clearInterval(timer)
                    }, 'analysisPoll')
                }
            },
        })),
        afterMount(({ actions, props, cache }) => {
            if (props.enabled && props.projectId > 0) {
                cache.disposables.add(() => {
                    actions.setScanClock(Date.now())
                    const timer = setInterval(() => actions.setScanClock(Date.now()), 30_000)
                    return () => clearInterval(timer)
                }, 'scanClock')
                actions.loadRecommendations()
            }
        }),
    ])
