type Busy = 'preview' | 'save' | 'verify' | null
type SaveStatus = 'idle' | 'unknown' | 'saved'
export type ConversionGoalNoticeState = 'idle' | 'preview' | 'save' | 'verify' | 'error' | 'review' | 'saved'

export function previewRequestFromTool(input: Record<string, unknown> | null): ConversionGoalPreviewApi | null {
    if (
        !input ||
        !input.goal ||
        typeof input.goal !== 'object' ||
        Array.isArray(input.goal) ||
        typeof input.date_from !== 'string' ||
        typeof input.date_to !== 'string'
    ) {
        return null
    }
    // The backend validates the complete goal before its response can become a reviewable draft.
    return Object.fromEntries(
        Object.entries(input).filter(
            ([key, value]) =>
                [
                    'goal',
                    'date_from',
                    'date_to',
                    'lookback_window_days',
                    'allow_multiple_conversions_per_visitor',
                    'filter_test_accounts',
                    'exclude_direct_traffic',
                    'exclude_unattributed',
                ].includes(key) && value != null
        )
    ) as unknown as ConversionGoalPreviewApi
}

function sameGoal(left: ConversionGoalApi, right: ConversionGoalApi): boolean {
    const { conversion_goal_id: _leftId, response: _leftResponse, name: _leftName, ...leftDefinition } = left
    const { conversion_goal_id: _rightId, response: _rightResponse, name: _rightName, ...rightDefinition } = right
    return objectsEqual(leftDefinition, rightDefinition)
}

