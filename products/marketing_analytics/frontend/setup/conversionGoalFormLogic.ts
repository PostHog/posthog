export const conversionGoalFormLogic: LogicWrapper<conversionGoalFormLogicType> = kea<conversionGoalFormLogicType>([
    props({} as ConversionGoalFormLogicProps),
    key(({ projectId }: ConversionGoalFormLogicProps) => projectId),
    path((key) => ['products', 'marketing_analytics', 'setup', 'conversionGoalFormLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentTeamId', 'currentTeamLoading']],
        actions: [marketingAnalyticsSettingsLogic, ['addOrUpdateConversionGoal']],
    })),
    actions({
        selectRecommendation: (recommendation: ConversionRecommendationApi) => ({ recommendation }),
        setDraft: (
            filter: ConversionGoalFilter,
            recommendation: ConversionRecommendationApi | null,
            editing: boolean = false
        ) => ({
            filter,
            recommendation,
            editing,
        }),
        reviewGoal: (goalId: string) => ({ goalId }),
        setName: (name: string) => ({ name }),
        setFilter: (filter: ConversionGoalFilter) => ({ filter }),
        clearDraft: true,
        requestFormFocus: true,
        formFocused: true,
        saveGoal: true,
        saveStarted: (goal: ConversionGoalFilter) => ({ goal }),
        saveFinished: (error: string | null) => ({ error }),
    }),
    reducers({
        formFocusRequested: [
            false,
            {
                requestFormFocus: () => true,
                setDraft: () => true,
                formFocused: () => false,
                clearDraft: () => false,
            },
        ],
        filter: [
            defaultConversionGoalFilter,
            {
                setDraft: (_, { filter }) => filter,
                setFilter: (_, { filter }) => filter,
                saveStarted: (_, { goal }) => goal,
                clearDraft: () => defaultConversionGoalFilter,
            },
        ],
        name: [
            '',
            {
                setDraft: (_, { filter }) => filter.conversion_goal_name,
                setName: (_, { name }) => name,
                clearDraft: () => '',
            },
        ],
        recommendation: [
            null as ConversionRecommendationApi | null,
            {
                setDraft: (_, { recommendation }) => recommendation,
                clearDraft: () => null,
            },
        ],
        editingGoalId: [
            null as string | null,
            {
                setDraft: (_, { filter, editing }) => (editing ? filter.conversion_goal_id : null),
                clearDraft: () => null,
            },
        ],
        savingGoalId: [
            null as string | null,
            {
                saveStarted: (_, { goal }) => goal.conversion_goal_id,
                saveFinished: () => null,
            },
        ],
        saveError: [
            null as string | null,
            {
                saveFinished: (_, { error }) => error,
                saveStarted: () => null,
                setDraft: () => null,
                clearDraft: () => null,
            },
        ],
    }),
    selectors(({ props }) => ({
        configuredGoals: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | TeamPublicType | null): ConversionGoalFilter[] =>
                currentTeam?.id === props.projectId
                    ? (currentTeam.marketing_analytics_config?.conversion_goals ?? [])
                    : [],
        ],
        findExistingGoal: [
            (s) => [s.configuredGoals],
            (
                goals: ConversionGoalFilter[]
            ): ((recommendation: ConversionRecommendationApi) => ConversionGoalFilter | undefined) =>
                (recommendation) => {
                    const candidate = recommendationToGoal(recommendation)
                    return (
                        findEquivalentConversionGoal(goals, candidate) ?? findConversionGoalForSource(goals, candidate)
                    )
                },
        ],
        duplicateGoal: [
            (s) => [s.configuredGoals, s.filter, s.editingGoalId],
            (
                goals: ConversionGoalFilter[],
                filter: ConversionGoalFilter,
                editingGoalId: string | null
            ): ConversionGoalFilter | null =>
                findEquivalentConversionGoal(
                    goals.filter((goal) => goal.conversion_goal_id !== editingGoalId),
                    withValidFlags(filter)
                ) ?? null,
        ],
        isFormValid: [
            (s) => [s.filter],
            (filter: ConversionGoalFilter): boolean =>
                filter.kind === NodeKind.EventsNode
                    ? !!filter.event
                    : filter.kind === NodeKind.ActionsNode
                      ? !!filter.id
                      : !!filter.table_name,
        ],
        isSaving: [(s) => [s.savingGoalId], (savingGoalId: string | null): boolean => savingGoalId !== null],
    })),
    listeners(({ actions, values, props }) => ({
        selectRecommendation: ({ recommendation }) => {
            if (!values.isSaving && !values.currentTeamLoading && values.currentTeamId === props.projectId) {
                const existingGoal = values.findExistingGoal(recommendation)
                actions.setDraft(existingGoal ?? recommendationToGoal(recommendation), recommendation, !!existingGoal)
            }
        },
        reviewGoal: ({ goalId }) => {
            const goal = values.configuredGoals.find((goal) => goal.conversion_goal_id === goalId)
            if (goal && !values.isSaving && !values.currentTeamLoading) {
                actions.setDraft(goal, values.recommendation, true)
            }
        },
        saveGoal: () => {
            if (
                !values.isFormValid ||
                values.isSaving ||
                values.currentTeamLoading ||
                values.currentTeamId !== props.projectId
            ) {
                return
            }
            const configuredSuggestion =
                values.recommendation && !values.editingGoalId
                    ? findConversionGoalForSource(values.configuredGoals, values.filter)
                    : undefined
            const existingGoal = values.duplicateGoal ?? configuredSuggestion
            if (existingGoal) {
                actions.reviewGoal(existingGoal.conversion_goal_id)
                return
            }
            if (
                values.editingGoalId &&
                !values.configuredGoals.some((goal) => goal.conversion_goal_id === values.editingGoalId)
            ) {
                actions.saveFinished('This conversion goal was removed. Clear the form to configure a new goal.')
                return
            }
            const goal = withValidFlags({
                ...values.filter,
                conversion_goal_id: values.filter.conversion_goal_id || uuid(),
                conversion_goal_name:
                    values.name.trim() || values.filter.custom_name || values.filter.name || 'No name',
            })
            actions.saveStarted(goal)
            actions.addOrUpdateConversionGoal(goal)
        },
        [teamLogic.actionTypes.updateCurrentTeamSuccess]: ({ currentTeam, payload }) => {
            if (
                currentTeam.id === props.projectId &&
                values.savingGoalId &&
                payload?.marketing_analytics_config?.conversion_goals?.some(
                    (goal: ConversionGoalFilter) => goal.conversion_goal_id === values.savingGoalId
                )
            ) {
                actions.saveFinished(null)
                actions.clearDraft()
            }
        },
        [teamLogic.actionTypes.updateCurrentTeamFailure]: () => {
            if (values.isSaving) {
                actions.saveFinished('Could not save this conversion goal. Review the settings and try again.')
            }
        },
    })),
])
