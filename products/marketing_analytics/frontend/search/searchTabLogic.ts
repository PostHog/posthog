import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'
import { subscriptions } from 'kea-subscriptions'

import type { PaginatedResponse } from 'lib/api'
import { FEATURE_FLAGS } from 'lib/constants'
import { dayjs, now } from 'lib/dayjs'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { userLogic } from 'scenes/userLogic'
import {
    MarketingAnalyticsTab,
    marketingAnalyticsLogic,
} from 'scenes/web-analytics/tabs/marketing-analytics/frontend/logic/marketingAnalyticsLogic'

import { ExternalDataSource, UserType } from '~/types'

import { RECOMMENDED_SEARCH_PLATFORMS, SEARCH_SOURCE_TYPES } from './searchPerformance'

// pinned: localStorage key - renaming it shows the tag again to every user
export const SEARCH_TAB_FIRST_SEEN_STORAGE_KEY = 'marketing-search-tab-first-seen-v1'
export const SEARCH_TAB_NEW_TAG_DAYS = 7

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface searchTabLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    activeTab: MarketingAnalyticsTab // marketingAnalyticsLogic
    dataWarehouseSources: PaginatedResponse<ExternalDataSource> | null // marketingAnalyticsLogic
    user: UserType | null // userLogic
    firstSeenAtByUser: Record<number, string>
    searchTabVisible: boolean
    showNewTag: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface searchTabLogicActions {
    reportSearchNewTagShown: () => {
        value: true
    } // marketingAnalyticsLogic
    markSeen: (
        userId: number,
        seenAt: string
    ) => {
        seenAt: string
        userId: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface searchTabLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        searchTabVisible: (
            featureFlags: FeatureFlagsSet,
            dataWarehouseSources: PaginatedResponse<ExternalDataSource> | null
        ) => boolean
        showNewTag: (
            searchTabVisible: boolean,
            user: UserType | null,
            dataWarehouseSources: PaginatedResponse<ExternalDataSource> | null,
            firstSeenAtByUser: Record<number, string>
        ) => boolean
    }
}

export type searchTabLogicType = MakeLogicType<
    searchTabLogicValues,
    searchTabLogicActions,
    Record<string, any>,
    searchTabLogicMeta
>

export const searchTabLogic = kea<searchTabLogicType>([
    path(['products', 'marketing_analytics', 'frontend', 'search', 'searchTabLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            userLogic,
            ['user'],
            marketingAnalyticsLogic,
            ['activeTab', 'dataWarehouseSources'],
        ],
        actions: [marketingAnalyticsLogic, ['reportSearchNewTagShown']],
    })),
    actions({
        markSeen: (userId: number, seenAt: string) => ({ userId, seenAt }),
    }),
    reducers({
        firstSeenAtByUser: [
            {} as Record<number, string>,
            { persist: true, storageKey: SEARCH_TAB_FIRST_SEEN_STORAGE_KEY },
            {
                markSeen: (state, { userId, seenAt }) => (state[userId] ? state : { ...state, [userId]: seenAt }),
            },
        ],
    }),
    selectors({
        searchTabVisible: [
            (s) => [s.featureFlags, s.dataWarehouseSources],
            (
                featureFlags: FeatureFlagsSet,
                dataWarehouseSources: PaginatedResponse<ExternalDataSource> | null
            ): boolean =>
                !!featureFlags[FEATURE_FLAGS.MARKETING_ANALYTICS_ORGANIC_KEYWORDS] &&
                !!dataWarehouseSources?.results.some((source) => SEARCH_SOURCE_TYPES.includes(source.source_type)),
        ],
        showNewTag: [
            (s) => [s.searchTabVisible, s.user, s.dataWarehouseSources, s.firstSeenAtByUser],
            (
                searchTabVisible: boolean,
                user: UserType | null,
                dataWarehouseSources: PaginatedResponse<ExternalDataSource> | null,
                firstSeenAtByUser: Record<number, string>
            ): boolean => {
                if (!searchTabVisible || !user || !dataWarehouseSources) {
                    return false
                }
                const connected = new Set(dataWarehouseSources.results.map((source) => source.source_type))
                if (RECOMMENDED_SEARCH_PLATFORMS.every((platform) => connected.has(platform))) {
                    return false
                }
                const firstSeenAt = firstSeenAtByUser[user.id]
                return !firstSeenAt || now().diff(dayjs(firstSeenAt), 'day') < SEARCH_TAB_NEW_TAG_DAYS
            },
        ],
    }),
    subscriptions(({ actions, values }) => {
        const markSeenIfOnSearch = (): void => {
            if (
                values.user &&
                values.searchTabVisible &&
                values.activeTab === MarketingAnalyticsTab.SEARCH_PERFORMANCE
            ) {
                actions.markSeen(values.user.id, now().toISOString())
            }
        }
        return {
            activeTab: markSeenIfOnSearch,
            user: markSeenIfOnSearch,
            searchTabVisible: markSeenIfOnSearch,
            showNewTag: (showNewTag: boolean, previous: boolean | undefined) => {
                if (showNewTag && !previous) {
                    actions.reportSearchNewTagShown()
                }
            },
        }
    }),
])
