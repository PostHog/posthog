function recommendation(
    overrides: Partial<MarketingAnalyticsRecommendation> &
        Pick<MarketingAnalyticsRecommendation, 'rule' | 'subject' | 'action' | 'reason'>
): MarketingAnalyticsRecommendation {
    return {
        level: 'search_term',
        impact: null,
        impactDirection: 'save',
        impactType: 'measured',
        currency: 'USD',
        ...overrides,
    }
}

function cpa(
    value: number | null,
    benchmark: number,
    benchmarkSource: MarketingAnalyticsRecommendationCpaBenchmarkSource
): MarketingAnalyticsRecommendationCpa {
    return { value, benchmark, benchmarkSource, bestCampaign: 62, worstCampaign: 412 }
}

