import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { userLogic } from 'scenes/userLogic'
import { getEnabledNativeMarketingSources } from 'scenes/web-analytics/tabs/marketing-analytics/frontend/logic/utils'

import { NativeMarketingSource } from '~/queries/schema/schema-general'
import { UserType } from '~/types'

// Persisted on the user; changing this key shows the announcement again everywhere.
export const NEW_AD_SOURCES_SEEN_KEY = 'marketing-new-ad-sources-v1'

const NEW_AD_SOURCES = new Set<NativeMarketingSource>(['AppleSearchAds', 'OpenAIAds', 'AmazonAds'])

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newAdSourcesLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    user: UserType | null // userLogic
    dismissedUserId: number | null
    newSources: readonly NativeMarketingSource[]
    showNotice: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newAdSourcesLogicActions {
    updateHasSeenProductIntroFor: (
        productKey: string,
        value?: boolean | undefined
    ) => {
        productKey: string
        value: boolean
    } // userLogic
    dismissNotice: () => {
        value: true
    }
    setDismissedUserId: (userId: number) => {
        userId: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newAdSourcesLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        newSources: (featureFlags: FeatureFlagsSet) => readonly NativeMarketingSource[]
        showNotice: (
            user: UserType | null,
            newSources: readonly (
                | 'AmazonAds'
                | 'AppleSearchAds'
                | 'BingAds'
                | 'GoogleAds'
                | 'LinkedinAds'
                | 'MetaAds'
                | 'OpenAIAds'
                | 'PinterestAds'
                | 'RedditAds'
                | 'RoktAds'
                | 'SnapchatAds'
                | 'TikTokAds'
            )[],
            dismissedUserId: number | null
        ) => boolean
    }
}

export type newAdSourcesLogicType = MakeLogicType<
    newAdSourcesLogicValues,
    newAdSourcesLogicActions,
    Record<string, any>,
    newAdSourcesLogicMeta
>

export const newAdSourcesLogic = kea<newAdSourcesLogicType>([
    path(['products', 'marketing_analytics', 'frontend', 'components', 'newAdSourcesLogic']),
    connect({
        values: [featureFlagLogic, ['featureFlags'], userLogic, ['user']],
        actions: [userLogic, ['updateHasSeenProductIntroFor']],
    }),
    actions({ dismissNotice: true, setDismissedUserId: (userId: number) => ({ userId }) }),
    reducers({
        dismissedUserId: [null as number | null, { setDismissedUserId: (_, { userId }) => userId }],
    }),
    selectors({
        newSources: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): readonly NativeMarketingSource[] =>
                getEnabledNativeMarketingSources(featureFlags).filter((source) => NEW_AD_SOURCES.has(source)),
        ],
        showNotice: [
            (s) => [s.user, s.newSources, s.dismissedUserId],
            (
                user: UserType | null,
                newSources: readonly NativeMarketingSource[],
                dismissedUserId: number | null
            ): boolean =>
                !!user &&
                newSources.length > 0 &&
                dismissedUserId !== user.id &&
                !user.has_seen_product_intro_for?.[NEW_AD_SOURCES_SEEN_KEY],
        ],
    }),
    listeners(({ actions, values }) => ({
        dismissNotice: () => {
            if (values.user && values.showNotice) {
                actions.setDismissedUserId(values.user.id)
                actions.updateHasSeenProductIntroFor(NEW_AD_SOURCES_SEEN_KEY)
            }
        },
    })),
])
