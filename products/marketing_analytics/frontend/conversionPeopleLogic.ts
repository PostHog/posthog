import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import * as api from './generated/api'
import { ConversionPeopleRequestApi, ConversionPeopleResponseApi } from './generated/api.schemas'

export interface ConversionPeopleLogicProps {
    request: ConversionPeopleRequestApi
}

export interface ConversionPeoplePage extends ConversionPeopleResponseApi {
    failed?: boolean
}

const emptyPage: ConversionPeoplePage = { results: [], has_more: false, preparing: false }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface conversionPeopleLogicValues {
    currentTeamId: number | null // teamLogic
    page: ConversionPeoplePage
    pageLoading: boolean
    search: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface conversionPeopleLogicActions {
    loadPeople: ({ append }: { append?: boolean }) => {
        append?: boolean
    }
    loadPeopleFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadPeopleSuccess: (
        page: ConversionPeoplePage,
        payload?: {
            append?: boolean
        }
    ) => {
        page: ConversionPeoplePage
        payload?: {
            append?: boolean
        }
    }
    setSearch: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface conversionPeopleLogicMeta {
    key: string
}

export type conversionPeopleLogicType = MakeLogicType<
    conversionPeopleLogicValues,
    conversionPeopleLogicActions,
    ConversionPeopleLogicProps,
    conversionPeopleLogicMeta
>

export const conversionPeopleLogic = kea<conversionPeopleLogicType>([
    props({} as ConversionPeopleLogicProps),
    key(({ request }) => JSON.stringify(request)),
    path((key) => ['products', 'marketing_analytics', 'conversionPeopleLogic', key]),
    connect({ values: [teamLogic, ['currentTeamId']] }),
    actions({ setSearch: (search: string) => ({ search }) }),
    loaders(({ props, values }) => ({
        page: [
            emptyPage,
            {
                loadPeople: async ({ append }: { append?: boolean }, breakpoint): Promise<ConversionPeoplePage> => {
                    await breakpoint(250)
                    let response: ConversionPeopleResponseApi
                    try {
                        response = await api.marketingAnalyticsConversionPeopleCreate(String(values.currentTeamId), {
                            ...props.request,
                            search: values.search,
                            after: append ? values.page.results.at(-1)?.id : undefined,
                            limit: 50,
                        })
                    } catch {
                        breakpoint()
                        return { ...(append ? values.page : emptyPage), failed: true }
                    }
                    breakpoint()
                    return {
                        ...response,
                        results: append ? [...values.page.results, ...response.results] : response.results,
                    }
                },
            },
        ],
    })),
    reducers({ search: ['', { setSearch: (_, { search }) => search }] }),
    listeners(({ actions }) => ({ setSearch: () => actions.loadPeople({}) })),
    afterMount(({ actions }) => actions.loadPeople({})),
])
