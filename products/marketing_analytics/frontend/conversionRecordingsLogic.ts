import { MakeLogicType, afterMount, connect, kea, key, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiError } from 'lib/api'
import { inStorybook, inStorybookTestRunner, uuid } from 'lib/utils/dom'
import { teamLogic } from 'scenes/teamLogic'

import * as api from './generated/api'
import { ConversionRecordingsRequestApi, ConversionRecordingsResponseApi } from './generated/api.schemas'

export interface ConversionRecordingsLogicProps {
    request: ConversionRecordingsRequestApi
}

export interface ConversionRecordingsPage extends ConversionRecordingsResponseApi {
    pageIndex: number
    cursors: string[]
    retryPage?: number
    errorMessage?: string
    queryId?: string
}

const emptyPage: ConversionRecordingsPage = {
    session_ids: [],
    has_more: false,
    preparing: false,
    pageIndex: 0,
    cursors: [],
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface conversionRecordingsLogicValues {
    currentTeamId: number | null // teamLogic
    page: ConversionRecordingsPage
    pageLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface conversionRecordingsLogicActions {
    loadSessions: (payload: { pageIndex?: number }) => {
        pageIndex?: number
    }
    loadSessionsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSessionsSuccess: (
        page: ConversionRecordingsPage,
        payload?: {
            pageIndex?: number
        }
    ) => {
        page: ConversionRecordingsPage
        payload?: {
            pageIndex?: number
        }
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface conversionRecordingsLogicMeta {
    key: string
}

export type conversionRecordingsLogicType = MakeLogicType<
    conversionRecordingsLogicValues,
    conversionRecordingsLogicActions,
    ConversionRecordingsLogicProps,
    conversionRecordingsLogicMeta
>

export const conversionRecordingsLogic = kea<conversionRecordingsLogicType>([
    props({} as ConversionRecordingsLogicProps),
    key(({ request }) => JSON.stringify(request)),
    path((key) => ['products', 'marketing_analytics', 'conversionRecordingsLogic', key]),
    connect({ values: [teamLogic, ['currentTeamId']] }),
    loaders(({ props, values }) => ({
        page: [
            emptyPage,
            {
                loadSessions: async (
                    payload: { pageIndex?: number },
                    breakpoint
                ): Promise<ConversionRecordingsPage> => {
                    await breakpoint(250)
                    const pageIndex = payload.pageIndex ?? 0
                    const queryId =
                        inStorybook() || inStorybookTestRunner() ? '00000000-0000-4000-8000-000000000000' : uuid()
                    let response: ConversionRecordingsResponseApi
                    try {
                        response = await api.marketingAnalyticsConversionRecordingsList(String(values.currentTeamId), {
                            ...props.request,
                            client_query_id: queryId,
                            after: pageIndex > 0 ? values.page.cursors[pageIndex - 1] : undefined,
                            limit: 100,
                        })
                    } catch (error) {
                        breakpoint()
                        return {
                            ...values.page,
                            errorMessage:
                                (error instanceof ApiError && error.detail) ||
                                "Couldn't load conversion recordings. Try again.",
                            preparing: false,
                            queryId,
                            retryPage: pageIndex,
                        }
                    }
                    breakpoint()
                    if (response.preparing) {
                        return {
                            ...values.page,
                            preparing: true,
                            errorMessage: undefined,
                            queryId,
                            retryPage: pageIndex,
                        }
                    }
                    return {
                        ...response,
                        pageIndex,
                        cursors: [
                            ...values.page.cursors.slice(0, pageIndex),
                            ...(response.has_more ? response.session_ids.slice(-1) : []),
                        ],
                    }
                },
            },
        ],
    })),
    afterMount(({ actions }) => actions.loadSessions({})),
])
