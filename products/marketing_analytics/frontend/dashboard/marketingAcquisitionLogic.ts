export type marketingAcquisitionLogicType = MakeLogicType<
    marketingAcquisitionLogicValues,
    marketingAcquisitionLogicActions,
    Record<string, any>,
    marketingAcquisitionLogicMeta
>

export const marketingAcquisitionLogic = kea<marketingAcquisitionLogicType>([
    path(['products', 'marketing_analytics', 'dashboard', 'marketingAcquisitionLogic']),
    connect(() => ({ values: [marketingAnalyticsSettingsLogic, ['conversion_goals']] })),
    actions({
        setCustomerGoalId: (customerGoalId: string) => ({ customerGoalId }),
        setTrafficChartMetric: (trafficChartMetric: TrafficChartMetric) => ({ trafficChartMetric }),
        toggleTrafficSort: (section: string, field: WebAnalyticsOrderByFields) => ({ section, field }),
    }),
    reducers({
        trafficOrderBy: [
            {} as Record<string, [WebAnalyticsOrderByFields, WebAnalyticsOrderByDirection]>,
            {
                toggleTrafficSort: (state, { section, field }) => ({
                    ...state,
                    [section]: [
                        field,
                        state[section]?.[0] === field && state[section]?.[1] === 'DESC' ? 'ASC' : 'DESC',
                    ],
                }),
            },
        ],
        customerGoalId: [null as string | null, { setCustomerGoalId: (_, { customerGoalId }) => customerGoalId }],
        trafficChartMetric: [
            'visitors' as TrafficChartMetric,
            { setTrafficChartMetric: (_, { trafficChartMetric }) => trafficChartMetric },
        ],
    }),
    selectors({
        customerGoals: [
            (s) => [s.conversion_goals],
            (goals: ConversionGoalFilter[]): ConversionGoalFilter[] =>
                attributableConversionGoals(goals).filter((goal) => goal.counts_as_customer),
        ],
        selectedCustomerGoal: [
            (s) => [s.customerGoalId, s.customerGoals],
            (id: string | null, goals: ConversionGoalFilter[]): ConversionGoalFilter | null =>
                goals.find((goal) => goal.conversion_goal_id === id) ?? goals[0] ?? null,
        ],
        customerConversionGoal: [
            (s) => [s.selectedCustomerGoal],
            (goal: ConversionGoalFilter | null): WebAnalyticsConversionGoal | null => {
                const properties = goal?.properties
                if (properties && !properties.every(isWebAnalyticsPropertyFilter)) {
                    return null
                }
                if (goal?.kind === NodeKind.ActionsNode) {
                    return { actionId: goal.id, properties }
                }
                if (goal?.kind === NodeKind.EventsNode && goal.event) {
                    return { customEventName: goal.event, properties }
                }
                return null
            },
        ],
        trafficChartSeries: [
            (s) => [s.trafficChartMetric, s.customerConversionGoal],
            (metric: TrafficChartMetric, goal: WebAnalyticsConversionGoal | null): EventsNode | ActionsNode =>
                trafficChartSeries(metric, goal),
        ],
    }),
])
