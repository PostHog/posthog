interface WebStatsBase {
    kind: NodeKind.WebStatsTableQuery
    breakdownBy: WebStatsBreakdown
    dateRange: DateRange
    compareFilter: CompareFilter
    properties: WebAnalyticsPropertyFilters
    filterTestAccounts: boolean
    orderBy: [WebAnalyticsOrderByFields, WebAnalyticsOrderByDirection]
    limit: number
    tags: typeof MARKETING_ANALYTICS_DEFAULT_QUERY_TAGS
}

const webStatsBase = (
    breakdownBy: WebStatsBreakdown,
    dateRange: DateRange,
    compareFilter: CompareFilter,
    properties: WebAnalyticsPropertyFilters,
    filterTestAccounts: boolean
): WebStatsBase => ({
    kind: NodeKind.WebStatsTableQuery,
    breakdownBy,
    dateRange,
    compareFilter,
    properties,
    filterTestAccounts,
    orderBy: [WebAnalyticsOrderByFields.Visitors, 'DESC'],
    limit: MARKETING_TABLE_ROW_LIMIT,
    tags: MARKETING_ANALYTICS_DEFAULT_QUERY_TAGS,
})

export const marketingDashboardLogic = kea<marketingDashboardLogicType>([
    path(['products', 'marketing_analytics', 'dashboard', 'marketingDashboardLogic']),
    connect(() => ({
        values: [
            marketingAnalyticsLogic,
            ['dateFilter', 'shouldFilterTestAccounts', 'dashboardBreakdown', 'dashboardProperties'],
            marketingAnalyticsSettingsLogic,
            ['conversion_goals', 'overviewMetrics'],
            teamLogic,
            ['timezone'],
        ],
    })),
    actions({
        setConversionGoalId: (conversionGoalId: string) => ({ conversionGoalId }),
    }),
    reducers({
        conversionGoalId: [
            null as string | null,
            { setConversionGoalId: (_, { conversionGoalId }) => conversionGoalId },
        ],
    }),
    selectors({
        dateRange: [
            (s) => [s.dateFilter],
            (dateFilter: DateFilter): DateRange => ({
                date_from: dateFilter.dateFrom,
                date_to: dateFilter.dateTo,
            }),
        ],
        // "All time" has no preceding window to compare against, so the arrows and pills drop out
        // on their own rather than needing a control.
        compare: [(s) => [s.dateFilter], (dateFilter: DateFilter): boolean => dateFilter.dateFrom !== 'all'],
        compareFilter: [(s) => [s.compare], (compare: boolean): CompareFilter => ({ compare })],
        webStatsBreakdown: [
            (s) => [s.dashboardBreakdown],
            (breakdown: MarketingAnalyticsAttributionBreakdown): WebStatsBreakdown =>
                ATTRIBUTION_BREAKDOWN_TO_WEB_STATS[breakdown],
        ],
        breakdownLabel: [
            (s) => [s.dashboardBreakdown],
            (breakdown: MarketingAnalyticsAttributionBreakdown): string => BREAKDOWN_LABELS[breakdown],
        ],
        conversionGoals: [
            (s) => [s.conversion_goals],
            (goals: ConversionGoalFilter[]): ConversionGoalFilter[] => attributableConversionGoals(goals),
        ],
        selectedConversionGoal: [
            (s) => [s.conversionGoalId, s.conversionGoals],
            (id: string | null, goals: ConversionGoalFilter[]): ConversionGoalFilter | null =>
                goals.find((goal) => goal.conversion_goal_id === id) ??
                goals.find((goal) => goal.counts_as_customer) ??
                goals[0] ??
                null,
        ],
        conversionGoal: [
            (s) => [s.selectedConversionGoal],
            (goal: ConversionGoalFilter | null): WebAnalyticsConversionGoal | null => {
                const properties = goal?.properties
                if (properties && !properties.every(isWebAnalyticsPropertyFilter)) {
                    return null
                }
                if (goal?.kind === NodeKind.ActionsNode) {
                    return { actionId: goal.id, properties }
                }
                if (goal?.kind === NodeKind.EventsNode && goal.event) {
                    return { customEventName: goal.event, properties }
                }
                return null
            },
        ],
        revenueGoals: [
            (s) => [s.conversionGoals],
            (goals: ConversionGoalFilter[]): ConversionGoalFilter[] =>
                goals.filter((goal) => goal.counts_as_revenue && !revenueDisabledReason(goal)),
        ],
        webOverviewQuery: [
            (s) => [s.dateRange, s.compareFilter, s.dashboardProperties, s.shouldFilterTestAccounts],
            (
                dateRange: DateRange,
                compareFilter: CompareFilter,
                properties: WebAnalyticsPropertyFilters,
                filterTestAccounts: boolean
            ): WebOverviewQuery => ({
                kind: NodeKind.WebOverviewQuery,
                dateRange,
                compareFilter,
                properties,
                filterTestAccounts,
                tags: MARKETING_ANALYTICS_DEFAULT_QUERY_TAGS,
            }),
        ],
        // With a goal set the overview query answers conversions instead of traffic, so the two
        // run side by side rather than one replacing the other.
        conversionOverviewQuery: [
            (s) => [s.webOverviewQuery, s.conversionGoal],
            (query: WebOverviewQuery, conversionGoal: WebAnalyticsConversionGoal | null): WebOverviewQuery | null =>
                conversionGoal ? { ...query, conversionGoal } : null,
        ],
        retentionAcquisitionRange: [
            (s) => [s.dateFilter, s.timezone],
            (dateFilter: DateFilter, timezone: string): RetentionAcquisitionRange => {
                const to = dateFilter.dateTo ? dateStringToDayJs(dateFilter.dateTo, timezone) : null
                const from = dateFilter.dateFrom ? dateStringToDayJs(dateFilter.dateFrom, timezone) : null
                const end = to ?? dateStringToDayJs('-0d', timezone)
                if (end && (!from || end.diff(from, 'day') > RETENTION_MAX_ACQUISITION_DAYS)) {
                    return {
                        dateRange: {
                            date_from: end.subtract(RETENTION_MAX_ACQUISITION_DAYS, 'day').format('YYYY-MM-DD'),
                            date_to: dateFilter.dateTo,
                        },
                        clamped: true,
                    }
                }
                return { dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo }, clamped: false }
            },
        ],
        retentionQuery: [
            (s) => [
                s.retentionAcquisitionRange,
                s.compare,
                s.dashboardBreakdown,
                s.dashboardProperties,
                s.shouldFilterTestAccounts,
            ],
            (
                acquisitionRange: RetentionAcquisitionRange,
                compare: boolean,
                breakdownBy: MarketingAnalyticsAttributionBreakdown,
                properties: WebAnalyticsPropertyFilters,
                filterTestAccounts: boolean
            ): MarketingAnalyticsRetentionQuery => ({
                kind: NodeKind.MarketingAnalyticsRetentionQuery,
                summary: true,
                comparePreviousPeriod: compare,
                dateRange: acquisitionRange.dateRange,
                breakdownBy,
                onlyNewUsers: true,
                excludeDirectTraffic: false,
                excludeUnattributed: false,
                properties,
                filterTestAccounts,
                tags: MARKETING_ANALYTICS_DEFAULT_QUERY_TAGS,
            }),
        ],
        // Summed from the goals themselves rather than the marketing table, whose revenue counts
        // only conversions matched to a synced ad campaign.
        revenueQuery: [
            (s) => [s.revenueGoals, s.dateRange, s.compareFilter, s.dashboardProperties, s.shouldFilterTestAccounts],
            (
                revenueGoals: ConversionGoalFilter[],
                dateRange: DateRange,
                compareFilter: CompareFilter,
                properties: WebAnalyticsPropertyFilters,
                filterTestAccounts: boolean
            ): TrendsQuery | null => {
                if (!revenueGoals.length) {
                    return null
                }
                return {
                    kind: NodeKind.TrendsQuery,
                    dateRange,
                    compareFilter,
                    properties,
                    filterTestAccounts,
                    interval: 'day',
                    trendsFilter: { display: ChartDisplayType.BoldNumber },
                    tags: MARKETING_ANALYTICS_DEFAULT_QUERY_TAGS,
                    // attributableConversionGoals drops warehouse goals at runtime, but the union
                    // type still carries them, so narrow rather than assume.
                    series: revenueGoals.flatMap((goal): TrendsQuery['series'] => {
                        if (goal.kind === NodeKind.ActionsNode) {
                            return [
                                {
                                    kind: NodeKind.ActionsNode as const,
                                    id: goal.id,
                                    math: PropertyMathType.Sum,
                                    math_property: goal.math_property,
                                    properties: goal.properties,
                                },
                            ]
                        }
                        if (goal.kind === NodeKind.EventsNode) {
                            return [
                                {
                                    kind: NodeKind.EventsNode as const,
                                    event: goal.event,
                                    math: PropertyMathType.Sum,
                                    math_property: goal.math_property,
                                    properties: goal.properties,
                                },
                            ]
                        }
                        return []
                    }),
                } as TrendsQuery
            },
        ],
        overviewTableQuery: [
            (s) => [
                s.webStatsBreakdown,
                s.dateRange,
                s.compareFilter,
                s.dashboardProperties,
                s.shouldFilterTestAccounts,
                s.conversionGoal,
            ],
            (
                breakdownBy: WebStatsBreakdown,
                dateRange: DateRange,
                compareFilter: CompareFilter,
                properties: WebAnalyticsPropertyFilters,
                filterTestAccounts: boolean,
                conversionGoal: WebAnalyticsConversionGoal | null
            ): WebStatsTableQuery => ({
                ...webStatsBase(breakdownBy, dateRange, compareFilter, properties, filterTestAccounts),
                includeSessionDuration: true,
                conversionGoal,
            }),
        ],
        acquisitionTableQuery: [
            (s) => [
                s.webStatsBreakdown,
                s.dateRange,
                s.compareFilter,
                s.dashboardProperties,
                s.shouldFilterTestAccounts,
            ],
            (
                breakdownBy: WebStatsBreakdown,
                dateRange: DateRange,
                compareFilter: CompareFilter,
                properties: WebAnalyticsPropertyFilters,
                filterTestAccounts: boolean
            ): WebStatsTableQuery => ({
                ...webStatsBase(breakdownBy, dateRange, compareFilter, properties, filterTestAccounts),
                includeTrafficMetrics: true,
            }),
        ],
        engagementTableQuery: [
            (s) => [
                s.webStatsBreakdown,
                s.dateRange,
                s.compareFilter,
                s.dashboardProperties,
                s.shouldFilterTestAccounts,
            ],
            (
                breakdownBy: WebStatsBreakdown,
                dateRange: DateRange,
                compareFilter: CompareFilter,
                properties: WebAnalyticsPropertyFilters,
                filterTestAccounts: boolean
            ): WebStatsTableQuery => ({
                ...webStatsBase(breakdownBy, dateRange, compareFilter, properties, filterTestAccounts),
                includeTrafficMetrics: true,
                includeBounceRate: true,
                includeSessionDuration: true,
            }),
        ],
        conversionTableQuery: [
            (s) => [
                s.webStatsBreakdown,
                s.dateRange,
                s.compareFilter,
                s.dashboardProperties,
                s.shouldFilterTestAccounts,
                s.conversionGoal,
            ],
            (
                breakdownBy: WebStatsBreakdown,
                dateRange: DateRange,
                compareFilter: CompareFilter,
                properties: WebAnalyticsPropertyFilters,
                filterTestAccounts: boolean,
                conversionGoal: WebAnalyticsConversionGoal | null
            ): WebStatsTableQuery | null =>
                conversionGoal
                    ? {
                          ...webStatsBase(breakdownBy, dateRange, compareFilter, properties, filterTestAccounts),
                          includeTrafficMetrics: true,
                          conversionGoal,
                      }
                    : null,
        ],
    }),
])
