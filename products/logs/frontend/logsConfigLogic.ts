export type logsConfigLogicType = MakeLogicType<
    logsConfigLogicValues,
    logsConfigLogicActions,
    Record<string, any>,
    logsConfigLogicMeta
>

export const logsConfigLogic = kea<logsConfigLogicType>([
    path(['products', 'logs', 'frontend', 'logsConfigLogic']),
    connect({ values: [teamLogic, ['currentTeamId']] }),
    forms(({ actions, values }) => ({
        patternMessageKeys: {
            defaults: { keys: DEFAULT_LOGS_PATTERN_MESSAGE_KEYS },
            errors: ({ keys }) => {
                const cleaned = keys.map((key) => key.trim())
                const error =
                    cleaned.length > 10
                        ? 'Use at most 10 keys.'
                        : cleaned.some((key) => !key)
                          ? 'Keys cannot be blank.'
                          : cleaned.some((key) => key.length > 200)
                            ? 'Each key must be 200 characters or fewer.'
                            : new Set(cleaned).size !== cleaned.length
                              ? 'Keys must be unique.'
                              : undefined
                return { keys: error ? [error] : undefined }
            },
            submit: async ({ keys }) => {
                const config = await saveLogsConfig(values.currentTeamId, {
                    logs_pattern_message_keys: keys.map((key) => key.trim()),
                })
                actions.updateLogsConfigSuccess(config)
            },
        },
    })),
    loaders(({ values }) => ({
        logsConfig: [
            null as TeamLogsConfigApi | null,
            {
                loadLogsConfig: async (): Promise<TeamLogsConfigApi> => {
                    // nosemgrep: prefer-codegen-api
                    return await api.get(`api/projects/${values.currentTeamId}/logs_config/`)
                },
                updateLogsConfig: async (patch: Partial<TeamLogsConfigApi>): Promise<TeamLogsConfigApi> => {
                    return await saveLogsConfig(values.currentTeamId, patch)
                },
            },
        ],
    })),
    selectors({
        // Undefined until logs_config resolves — distinct-id detection falls back to its
        // built-in convention list (which contains the default) in the meantime.
        configuredDistinctIdKeys: [
            (s) => [s.logsConfig],
            (logsConfig: TeamLogsConfigApi | null): string[] | undefined => logsConfig?.logs_distinct_id_attribute_keys,
        ],
        // Undefined until logs_config resolves — session detection falls back to its
        // built-in convention list (which contains the default) in the meantime.
        configuredSessionIdKeys: [
            (s) => [s.logsConfig],
            (logsConfig: TeamLogsConfigApi | null): string[] | undefined => logsConfig?.logs_session_id_attribute_keys,
        ],
    }),
    listeners(({ actions }) => ({
        loadLogsConfigSuccess: ({ logsConfig }) => {
            actions.resetPatternMessageKeys({
                keys: logsConfig.logs_pattern_message_keys ?? DEFAULT_LOGS_PATTERN_MESSAGE_KEYS,
            })
        },
        updateLogsConfigSuccess: ({ logsConfig }) => {
            actions.resetPatternMessageKeys({
                keys: logsConfig.logs_pattern_message_keys ?? DEFAULT_LOGS_PATTERN_MESSAGE_KEYS,
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadLogsConfig()
    }),
])
