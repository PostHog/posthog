// How many exceptions each session on the current page hit, so a log row can say "this session hit
// errors" without the user opening the row's Related errors tab first. The count answers the
// session, not the log line: an exception in the same session is co-occurring evidence, not a cause.
//
// The count comes from raw `$exception` events, while the tab it opens resolves them into Error
// Tracking issues. So the badge counts events the tab may group, suppress, or filter out, and the
// two can disagree on the number.
export const logsSessionErrorsLogic = kea<logsSessionErrorsLogicType>([
    props({} as LogsSessionErrorsLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'logs', 'frontend', 'components', 'LogsViewer', 'logsSessionErrorsLogic', key]),

    connect(({ id }: LogsSessionErrorsLogicProps) => ({
        values: [
            logsViewerDataLogic({ id }),
            ['parsedLogs as logs'],
            logsConfigLogic,
            ['configuredSessionIdKeys'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [logsViewerDataLogic({ id }), ['fetchLogsSuccess', 'fetchNextLogsPageSuccess', 'setLogsSuccess']],
    })),

    loaders(({ values }) => ({
        sessionErrorCounts: [
            {} as Record<string, number>,
            {
                loadSessionErrorCounts: async (
                    { reset }: { reset: boolean },
                    breakpoint
                ): Promise<Record<string, number>> => {
                    // A fresh query replaces the result set, so drop what the previous filters answered.
                    const known = reset ? {} : values.sessionErrorCounts
                    // hasOwn, not `in`: `in` walks the prototype chain, so a session id that
                    // collides with an Object member would read as already answered.
                    const sessionIds = values.sessionIdsInView.filter((sessionId) => !Object.hasOwn(known, sessionId))
                    // Read the range off the same snapshot the ids came from, before the debounce,
                    // so a page that empties mid-wait cannot leave the two disagreeing.
                    const range = pageLookupWindow(values.logs)
                    if (sessionIds.length === 0 || !range) {
                        return known
                    }
                    await breakpoint(reset ? FIRST_LOOKUP_DEBOUNCE_MS : INCREMENTAL_LOOKUP_DEBOUNCE_MS)

                    const response = await api.queryHogQL(
                        hogql`
                            SELECT properties.$session_id AS session_id, count() AS exceptions
                            FROM events
                            WHERE event = '$exception'
                              AND timestamp >= ${range.from}
                              AND timestamp <= ${range.to}
                              AND properties.$session_id IN ${sessionIds}
                            GROUP BY session_id
                        `,
                        { scene: 'Logs', productKey: 'logs', name: 'logs_session_error_counts' }
                    )
                    breakpoint()

                    // Every session looked up gets an entry, including the ones with no exceptions.
                    // That is what stops the next page re-asking about sessions already answered.
                    const counts: Record<string, number> = Object.fromEntries(
                        sessionIds.map((sessionId) => [sessionId, 0])
                    )
                    for (const [sessionId, exceptions] of (response.results ?? []) as [string, number][]) {
                        counts[sessionId] = Number(exceptions)
                    }
                    return { ...known, ...counts }
                },
            },
        ],
    })),

    selectors({
        showSessionErrors: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.LOGS_SESSION_ERROR_BADGES],
        ],

        sessionIdsInView: [
            (s) => [s.logs, s.configuredSessionIdKeys],
            (logs: ParsedLogMessage[], configuredSessionIdKeys: string[] | undefined): string[] => {
                const sessionIds = logs
                    .map((log) =>
                        getSessionIdFromLogAttributes(log.attributes, log.resource_attributes, configuredSessionIdKeys)
                    )
                    .filter((sessionId): sessionId is string => !!sessionId)
                return Array.from(new Set(sessionIds)).slice(0, MAX_SESSIONS_PER_LOOKUP)
            },
        ],
    }),

    listeners(({ actions, values }) => {
        const lookUpNewSessions = (reset: boolean) => (): void => {
            if (values.showSessionErrors) {
                actions.loadSessionErrorCounts({ reset })
            }
        }
        return {
            fetchLogsSuccess: lookUpNewSessions(true),
            fetchNextLogsPageSuccess: lookUpNewSessions(false),
            setLogsSuccess: lookUpNewSessions(false),
        }
    }),
])
