// How many exceptions each session on the current page hit, so a log row can say "this session hit
// errors" without the user opening the row's Related errors tab first. The count answers the
// session, not the log line: an exception in the same session is co-occurring evidence, not a cause.
export const logsSessionErrorsLogic = kea<logsSessionErrorsLogicType>([
    props({} as LogsSessionErrorsLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'logs', 'frontend', 'components', 'LogsViewer', 'logsSessionErrorsLogic', key]),

    connect(({ id }: LogsSessionErrorsLogicProps) => ({
        values: [
            logsViewerDataLogic({ id }),
            ['parsedLogs as logs'],
            logsConfigLogic,
            ['configuredSessionIdKeys'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [logsViewerDataLogic({ id }), ['fetchLogsSuccess', 'fetchNextLogsPageSuccess', 'setLogsSuccess']],
    })),

    loaders(({ values }) => ({
        sessionErrorCounts: [
            {} as Record<string, number>,
            {
                loadSessionErrorCounts: async (
                    { reset }: { reset: boolean },
                    breakpoint
                ): Promise<Record<string, number>> => {
                    const known = reset ? {} : values.sessionErrorCounts
                    const sessionIds = reset ? values.sessionIdsInView : values.unresolvedSessionIds
                    const window = values.lookupWindow
                    if (sessionIds.length === 0 || !window) {
                        return known
                    }
                    // Collapse the burst a fast scroll produces into one query per settled page.
                    await breakpoint(300)

                    const sessionIdList = sessionIds.map((sessionId) => hogql`${sessionId}`).join(', ')
                    const response = await api.queryHogQL(
                        hogql`
                            SELECT properties.$session_id AS session_id, count() AS exceptions
                            FROM events
                            WHERE event = '$exception'
                              AND timestamp >= ${window.from}
                              AND timestamp <= ${window.to}
                              AND properties.$session_id IN (${hogql.raw(sessionIdList)})
                            GROUP BY session_id
                        `,
                        { scene: 'Logs', productKey: 'logs', name: 'logs_session_error_counts' }
                    )
                    breakpoint()

                    // Every session looked up gets an entry, including the ones with no exceptions —
                    // that's what stops the next page re-asking about sessions already answered.
                    const counts: Record<string, number> = Object.fromEntries(
                        sessionIds.map((sessionId) => [sessionId, 0])
                    )
                    for (const [sessionId, exceptions] of (response.results ?? []) as [string, number][]) {
                        counts[sessionId] = Number(exceptions)
                    }
                    return { ...known, ...counts }
                },
            },
        ],
    })),

    selectors({
        sessionIdsInView: [
            (s) => [s.logs, s.configuredSessionIdKeys, s.featureFlags],
            (
                logs: ParsedLogMessage[],
                configuredSessionIdKeys: string[] | undefined,
                featureFlags: FeatureFlagsSet
            ): string[] => {
                if (!featureFlags[FEATURE_FLAGS.LOGS_SESSION_ERROR_BADGES]) {
                    return []
                }
                const sessionIds: string[] = []
                const seen = new Set<string>()
                for (const log of logs) {
                    const sessionId = getSessionIdFromLogAttributes(
                        log.attributes,
                        log.resource_attributes,
                        configuredSessionIdKeys
                    )
                    if (sessionId && !seen.has(sessionId)) {
                        seen.add(sessionId)
                        sessionIds.push(sessionId)
                    }
                    if (sessionIds.length >= MAX_SESSIONS_PER_LOOKUP) {
                        break
                    }
                }
                return sessionIds
            },
        ],

        lookupWindow: [
            (s) => [s.logs],
            (logs: ParsedLogMessage[]): SessionErrorsWindow | null => {
                if (logs.length === 0) {
                    return null
                }
                // Logs arrive newest-first or oldest-first depending on the sort, so scan rather
                // than trusting the ends.
                let earliest = dayjs(logs[0].timestamp)
                let latest = earliest
                for (const log of logs) {
                    const timestamp = dayjs(log.timestamp)
                    if (timestamp.isBefore(earliest)) {
                        earliest = timestamp
                    }
                    if (timestamp.isAfter(latest)) {
                        latest = timestamp
                    }
                }
                return {
                    from: earliest.subtract(LOOKUP_WINDOW_HOURS, 'hours').toISOString(),
                    to: latest.add(LOOKUP_WINDOW_HOURS, 'hours').toISOString(),
                }
            },
        ],

        unresolvedSessionIds: [
            (s) => [s.sessionIdsInView, s.sessionErrorCounts],
            (sessionIdsInView: string[], sessionErrorCounts: Record<string, number>): string[] =>
                sessionIdsInView.filter((sessionId) => !(sessionId in sessionErrorCounts)),
        ],
    }),

    listeners(({ actions }) => ({
        // A fresh query replaces the result set, so drop what the previous filters answered.
        fetchLogsSuccess: () => actions.loadSessionErrorCounts({ reset: true }),
        fetchNextLogsPageSuccess: () => actions.loadSessionErrorCounts({ reset: false }),
        setLogsSuccess: () => actions.loadSessionErrorCounts({ reset: false }),
    })),
])
