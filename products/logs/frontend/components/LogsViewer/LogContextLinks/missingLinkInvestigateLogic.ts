import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import posthog from 'posthog-js'

import { copyToClipboard } from 'lib/utils/copyToClipboard'
import { MAX_SIDE_PANEL_ID } from 'scenes/max/components/PhaiSidePanelChat'
import { PhaiViewMode, maxGlobalLogic } from 'scenes/max/maxGlobalLogic'

import { sidePanelStateLogic } from '~/layout/navigation-3000/sidepanel/sidePanelStateLogic'
import { SidePanelTab } from '~/types'

import { ParsedLogMessage } from 'products/logs/frontend/types'
import { type ComposerSeed, composerSeedLogic, runnerPanelLogic } from 'products/posthog_ai/frontend/api/logics'

import type { LogContextLinksSurface } from './LogContextLinks'
import { MissingLink, buildMissingLinkPrompt } from './missingLinkPrompt'

export type MissingLinkInvestigateOption = 'copy_prompt' | 'posthog_ai_task'

