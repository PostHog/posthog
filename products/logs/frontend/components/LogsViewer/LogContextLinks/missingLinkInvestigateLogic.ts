export const missingLinkInvestigateLogic = kea<missingLinkInvestigateLogicType>([
    path([
        'products',
        'logs',
        'frontend',
        'components',
        'LogsViewer',
        'LogContextLinks',
        'missingLinkInvestigateLogic',
    ]),

    connect(() => ({
        values: [
            maxGlobalLogic,
            ['dataProcessingAccepted', 'effectivePhaiView'],
            todayShellLogic,
            ['todayRailEnabled'],
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['seed'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['activeCreation'],
        ],
        actions: [
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setSeed'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['clearActiveCreation', 'setHistoryExpanded'],
            sidePanelStateLogic,
            ['openSidePanel'],
            maxGlobalLogic,
            ['askSidePanelMax'],
            logsViewerModalLogic,
            ['closeLogsViewerModal'],
        ],
    })),

    actions({
        startTask: (prompt: string, closeHost: () => void) => ({ prompt, closeHost }),
    }),

    selectors({
        // Only the new view's side panel turns a seed into a task. The rail moves PostHog AI to its own
        // scene, and the legacy view has no tasks, so both of those take the prompt as a chat question.
        startsSidePanelTask: [
            (s) => [s.effectivePhaiView, s.todayRailEnabled],
            (effectivePhaiView: PhaiViewMode, todayRailEnabled: boolean): boolean =>
                effectivePhaiView === 'new' && !todayRailEnabled,
        ],
        // The side panel holds a seed it has not taken yet, and submits it after any submission in flight,
        // so a second launch now would queue a duplicate task. A creation without a task ID is still
        // submitting: success adds the ID and failure clears the creation, which ends the guard either way.
        launching: [
            (s) => [s.seed, s.activeCreation],
            (seed: ComposerSeed | null, activeCreation: ActiveCreation | null): boolean =>
                !!seed?.autoSubmit || (!!activeCreation && !activeCreation.taskId),
        ],
    }),

    listeners(({ actions, values }) => ({
        startTask: ({ prompt, closeHost }) => {
            // The drawer and the logs modal sit above the side panel, so close them before it opens.
            closeHost()
            actions.closeLogsViewerModal()
            if (values.todayRailEnabled) {
                // The rail keeps PostHog AI in the /ai scene, in the same tab. Its `ask` seeds a task in the
                // new view and starts a chat in the legacy view, and both remove the prompt from the URL.
                router.actions.push(urls.ai(undefined, prompt))
                return
            }
            if (!values.startsSidePanelTask) {
                // The legacy view: the shared ask path opens the question in a new PostHog AI tab.
                actions.askSidePanelMax(prompt)
                return
            }
            if (values.launching) {
                // Show the investigation already starting rather than queueing a second one.
                actions.openSidePanel(SidePanelTab.Max)
                return
            }
            // A fresh task, so the prompt never lands in whatever run the panel last showed.
            actions.clearActiveCreation()
            actions.setHistoryExpanded(false)
            // A one-shot seed, not an `openSidePanel` option, which would sit in the URL and rerun on refresh.
            actions.setSeed({ prompt, autoSubmit: values.dataProcessingAccepted })
            actions.openSidePanel(SidePanelTab.Max)
        },
    })),
])
