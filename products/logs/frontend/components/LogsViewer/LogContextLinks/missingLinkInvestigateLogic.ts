import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { MAX_SIDE_PANEL_ID } from 'scenes/max/components/PhaiSidePanelChat'
import { maxGlobalLogic } from 'scenes/max/maxGlobalLogic'

import { sidePanelStateLogic } from '~/layout/navigation-3000/sidepanel/sidePanelStateLogic'
import { SidePanelTab } from '~/types'

import { logsViewerModalLogic } from 'products/logs/frontend/components/LogsViewer/LogsViewerModal/logsViewerModalLogic'
import { type ComposerSeed, composerSeedLogic, runnerPanelLogic } from 'products/posthog_ai/frontend/api/logics'

// How long a second click is ignored after a launch, covering the side panel's task creation request.
const LAUNCH_GUARD_MS = 5000

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface missingLinkInvestigateLogicValues {
    dataProcessingAccepted: boolean // maxGlobalLogic
    launching: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface missingLinkInvestigateLogicActions {
    setSeed: (seed: ComposerSeed) => {
        seed: ComposerSeed
    } // composerSeedLogic
    closeLogsViewerModal: () => {
        value: true
    } // logsViewerModalLogic
    clearActiveCreation: () => {
        value: true
    } // runnerPanelLogic
    setHistoryExpanded: (expanded: boolean) => {
        expanded: boolean
    } // runnerPanelLogic
    openSidePanel: (
        tab: SidePanelTab,
        options?: string | undefined
    ) => {
        options: string | undefined
        tab: SidePanelTab
    } // sidePanelStateLogic
    releaseLaunch: () => {
        value: true
    }
    startTask: (
        prompt: string,
        closeHost: () => void
    ) => {
        closeHost: () => void
        prompt: string
    }
}

export type missingLinkInvestigateLogicType = MakeLogicType<
    missingLinkInvestigateLogicValues,
    missingLinkInvestigateLogicActions
>

export const missingLinkInvestigateLogic = kea<missingLinkInvestigateLogicType>([
    path([
        'products',
        'logs',
        'frontend',
        'components',
        'LogsViewer',
        'LogContextLinks',
        'missingLinkInvestigateLogic',
    ]),

    connect(() => ({
        values: [maxGlobalLogic, ['dataProcessingAccepted']],
        actions: [
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setSeed'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['clearActiveCreation', 'setHistoryExpanded'],
            sidePanelStateLogic,
            ['openSidePanel'],
            logsViewerModalLogic,
            ['closeLogsViewerModal'],
        ],
    })),

    actions({
        startTask: (prompt: string, closeHost: () => void) => ({ prompt, closeHost }),
        releaseLaunch: true,
    }),

    reducers({
        launching: [
            false,
            {
                startTask: () => true,
                releaseLaunch: () => false,
            },
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        startTask: ({ prompt, closeHost }) => {
            // The drawer and the logs modal sit above the side panel, so close them before it opens.
            closeHost()
            actions.closeLogsViewerModal()
            // A fresh task, so the prompt never lands in whatever run the panel last showed.
            actions.clearActiveCreation()
            actions.setHistoryExpanded(false)
            // A one-shot seed, not an `openSidePanel` option, which would sit in the URL and rerun on refresh.
            actions.setSeed({ prompt, autoSubmit: values.dataProcessingAccepted })
            actions.openSidePanel(SidePanelTab.Max)
            cache.disposables.add(() => {
                const timeout = setTimeout(() => actions.releaseLaunch(), LAUNCH_GUARD_MS)
                return () => clearTimeout(timeout)
            }, 'launchGuard')
        },
    })),
])
