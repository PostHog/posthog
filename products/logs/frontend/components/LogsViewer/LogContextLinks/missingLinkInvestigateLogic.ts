export type missingLinkInvestigateLogicType = MakeLogicType<
    missingLinkInvestigateLogicValues,
    missingLinkInvestigateLogicActions,
    Record<string, any>,
    missingLinkInvestigateLogicMeta
>

function captureInvestigate(
    option: MissingLinkInvestigateOption,
    log: ParsedLogMessage,
    missing: MissingLink[],
    surface: LogContextLinksSurface
): void {
    // pinned: analytics event name and properties, renaming breaks dashboards
    posthog.capture('logs missing link investigate clicked', {
        option,
        missing,
        source: `log-${surface}`,
        service_name: log.resource_attributes?.['service.name'] ?? null,
    })
}

export const missingLinkInvestigateLogic = kea<missingLinkInvestigateLogicType>([
    path([
        'products',
        'logs',
        'frontend',
        'components',
        'LogsViewer',
        'LogContextLinks',
        'missingLinkInvestigateLogic',
    ]),

    connect(() => ({
        values: [maxGlobalLogic, ['isMaxAvailable', 'effectivePhaiView', 'dataProcessingAccepted']],
        actions: [
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setSeed'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['clearActiveCreation', 'setHistoryExpanded'],
            sidePanelStateLogic,
            ['openSidePanel'],
        ],
    })),

    actions({
        copyPrompt: (log: ParsedLogMessage, missing: MissingLink[], surface: LogContextLinksSurface) => ({
            log,
            missing,
            surface,
        }),
        startTask: (log: ParsedLogMessage, missing: MissingLink[], surface: LogContextLinksSurface) => ({
            log,
            missing,
            surface,
        }),
    }),

    selectors({
        // Tasks run only in the sandbox view; the legacy chat cannot read code or open a pull request.
        taskDisabledReason: [
            (s) => [s.isMaxAvailable, s.effectivePhaiView],
            (isMaxAvailable: boolean, effectivePhaiView: PhaiViewMode): string | null =>
                !isMaxAvailable
                    ? 'PostHog AI is not available in this project'
                    : effectivePhaiView !== 'new'
                      ? 'Switch PostHog AI to the new view to run tasks'
                      : null,
        ],
    }),

    listeners(({ actions, values }) => ({
        copyPrompt: async ({ log, missing, surface }) => {
            captureInvestigate('copy_prompt', log, missing, surface)
            await copyToClipboard(buildMissingLinkPrompt(log, missing), 'prompt')
        },
        startTask: ({ log, missing, surface }) => {
            if (values.taskDisabledReason) {
                return
            }
            captureInvestigate('posthog_ai_task', log, missing, surface)
            // Start a fresh task so the prompt never lands in whatever run the panel last showed.
            actions.clearActiveCreation()
            actions.setHistoryExpanded(false)
            actions.setSeed({
                prompt: buildMissingLinkPrompt(log, missing),
                autoSubmit: values.dataProcessingAccepted,
            })
            actions.openSidePanel(SidePanelTab.Max)
        },
    })),
])
