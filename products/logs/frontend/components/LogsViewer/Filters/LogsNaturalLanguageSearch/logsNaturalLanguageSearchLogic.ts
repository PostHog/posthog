    setFilters: (
        filters: Partial<LogsViewerFilters>,
        pushToHistory?: boolean | undefined
    ) => {
        filters: Partial<LogsViewerFilters>
        pushToHistory: boolean
    } // logsViewerFiltersLogic
    applyCandidate: (
        candidate: _LogsNaturalLanguageCandidateApi,
        rank: number,
        automatic: boolean
    ) => {
        automatic: boolean
        candidate: _LogsNaturalLanguageCandidateApi
        rank: number
    }
    askAi: (query: string) => {
        query: string
    }
    askAiFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    askAiSuccess: (
        response: LogsNaturalLanguageQueryResponseApi,
        payload?: {
            query: string
        }
    ) => {
        response: LogsNaturalLanguageQueryResponseApi
        payload?: {
            query: string
        }
    }
    reset: () => {
        value: true
    }
