import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { ApiError } from 'lib/api-error'
import { projectLogic } from 'scenes/projectLogic'

import { LogsViewerFilters } from 'products/logs/frontend/components/LogsViewer/config/types'
import { logsViewerFiltersLogic } from 'products/logs/frontend/components/LogsViewer/Filters/logsViewerFiltersLogic'
import { logsNaturalLanguageQueryCreate } from 'products/logs/frontend/generated/api'
import type {
    LogsNaturalLanguageQueryResponseApi,
    _LogsNaturalLanguageCandidateApi,
} from 'products/logs/frontend/generated/api.schemas'
import { logsQueryToViewerFilters } from 'products/logs/frontend/logsAgentContext'

import { shouldAutoApply } from './naturalLanguageSearch'

export interface LogsNaturalLanguageSearchLogicProps {
    id: string
}

