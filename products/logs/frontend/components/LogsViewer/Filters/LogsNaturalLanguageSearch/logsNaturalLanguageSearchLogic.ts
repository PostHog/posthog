// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsNaturalLanguageSearchLogicMeta {
    key: string
}

export type logsNaturalLanguageSearchLogicType = MakeLogicType<
    logsNaturalLanguageSearchLogicValues,
    logsNaturalLanguageSearchLogicActions,
    LogsNaturalLanguageSearchLogicProps,
    logsNaturalLanguageSearchLogicMeta
>

const FALLBACK_ERROR = "Couldn't turn that into filters. Try again, or search for a term instead."

export const logsNaturalLanguageSearchLogic = kea<logsNaturalLanguageSearchLogicType>([
    props({} as LogsNaturalLanguageSearchLogicProps),
    key((props) => props.id),
    path((key) => [
        'products',
        'logs',
        'frontend',
        'components',
        'LogsViewer',
        'Filters',
        'LogsNaturalLanguageSearch',
        'logsNaturalLanguageSearchLogic',
        key,
    ]),
    connect((props: LogsNaturalLanguageSearchLogicProps) => ({
        values: [projectLogic, ['currentProjectId'], logsViewerFiltersLogic({ id: props.id }), ['filters']],
        actions: [logsViewerFiltersLogic({ id: props.id }), ['setFilters']],
    })),
    actions({
        askAi: (query: string) => ({ query }),
        applyCandidate: (candidate: _LogsNaturalLanguageCandidateApi, rank: number, automatic: boolean) => ({
            candidate,
            rank,
            automatic,
        }),
        reset: true,
    }),
    loaders(({ values }) => ({
        response: [
            null as LogsNaturalLanguageQueryResponseApi | null,
            {
                askAi: async ({ query }, breakpoint) => {
                    const { date_from, date_to } = values.filters.dateRange
                    const response = await logsNaturalLanguageQueryCreate(String(values.currentProjectId), {
                        query,
                        dateRange: { date_from: date_from ?? null, date_to: date_to ?? null },
                    })
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers({
        response: { reset: () => null, applyCandidate: () => null },
        error: [
            null as string | null,
            {
                askAi: () => null,
                askAiFailure: (_, { errorObject }) =>
                    (errorObject instanceof ApiError && typeof errorObject.data?.error === 'string'
                        ? errorObject.data.error
                        : null) ?? FALLBACK_ERROR,
                reset: () => null,
            },
        ],
        appliedCount: [0, { applyCandidate: (count) => count + 1 }],
        askedQuery: [
            null as string | null,
            {
                askAi: (_, { query }) => query,
                reset: () => null,
                applyCandidate: () => null,
            },
        ],
    }),
    listeners(({ actions }) => ({
        askAiSuccess: ({ response }) => {
            if (response && response.candidates.length > 0 && shouldAutoApply(response)) {
                actions.applyCandidate(response.candidates[0], 0, true)
            }
        },
        applyCandidate: ({ candidate, rank, automatic }) => {
            actions.setFilters(logsQueryToViewerFilters({ query: candidate.query }))
            // pinned: analytics event name and properties, renaming breaks dashboards
            posthog.capture('logs natural language candidate applied', {
                rank,
                automatic,
                probability: candidate.probability,
                filter_count: candidate.query.filterGroup.length,
                has_service: candidate.query.serviceNames.length > 0,
                has_severity: candidate.query.severityLevels.length > 0,
            })
        },
    })),
])
