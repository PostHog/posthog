/**
 * The user's custom facets for logs, persisted server-side (per user, per team) so they follow the
 * user across devices. A singleton (not keyed by viewer id): the underlying setting is one row per
 * user/team/product, not one per rail instance.
 */
export const customFacetsLogic = kea<customFacetsLogicType>([
    path(['products', 'logs', 'frontend', 'components', 'LogsViewer', 'FacetRail', 'customFacetsLogic']),

    connect(() => ({ values: [featureFlagLogic, ['featureFlags']] })),

    actions({
        loadEntries: true,
        addCustomFacet: (key: string, sourceType: CustomFacetSourceType) => ({ key, sourceType }),
        removeCustomFacet: (key: string, sourceType: CustomFacetSourceType) => ({ key, sourceType }),
    }),

    loaders(({ values }) => ({
        entries: [
            [] as UserFacetSettingsEntryApi[],
            {
                loadEntries: async () => {
                    const response = await userFacetSettingsRetrieve('@me', { product: PRODUCT })
                    return response.custom_facets
                },
                addCustomFacet: async ({ key, sourceType }) => {
                    const sourceTypeApi = toSourceTypeApi(sourceType)
                    if (values.entries.some((entry) => entry.key === key && entry.source_type === sourceTypeApi)) {
                        return values.entries
                    }
                    const nextEntries = [...values.entries, { key, source_type: sourceTypeApi }]
                    await userFacetSettingsPartialUpdate('@me', { product: PRODUCT }, { custom_facets: nextEntries })
                    return nextEntries
                },
                removeCustomFacet: async ({ key, sourceType }) => {
                    const sourceTypeApi = toSourceTypeApi(sourceType)
                    const nextEntries = values.entries.filter(
                        (entry) => !(entry.key === key && entry.source_type === sourceTypeApi)
                    )
                    await userFacetSettingsPartialUpdate('@me', { product: PRODUCT }, { custom_facets: nextEntries })
                    return nextEntries
                },
            },
        ],
    })),

    selectors({
        customFacets: [
            (s) => [s.entries, s.featureFlags],
            (entries: UserFacetSettingsEntryApi[], featureFlags: FeatureFlagsSet): FacetConfig[] =>
                featureFlags[FEATURE_FLAGS.CUSTOM_FACET_PINNING]
                    ? entries.map((entry) =>
                          buildCustomFacet(
                              entry.key,
                              entry.source_type === UserFacetSettingsEntrySourceTypeEnumApi.Attribute
                                  ? 'attribute'
                                  : 'resourceAttribute'
                          )
                      )
                    : [],
        ],
    }),

    events(({ actions, values }) => ({
        afterMount: () => {
            if (values.featureFlags[FEATURE_FLAGS.CUSTOM_FACET_PINNING]) {
                actions.loadEntries()
            }
        },
    })),
])
