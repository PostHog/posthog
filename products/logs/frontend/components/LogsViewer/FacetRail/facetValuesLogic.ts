/**
 * One facet's values + counts, cross-filtered server-side: the results reflect every active filter
 * except this facet's own selection, which the backend strips from the WHERE clause.
 *
 * One instance per facet, so each fetches on its own schedule and holds its own loading state. What
 * it fetches on is `fetchSignature` — the scope with this facet's own filters removed, plus its
 * type-ahead — so clicking a value here re-scopes the *other* facets and leaves this list alone.
 */
export const facetValuesLogic = kea<facetValuesLogicType>([
    props({} as FacetValuesLogicProps),
    // The resolved source key is part of the key: when alias resolution moves a facet onto another
    // attribute spelling, that's a different query, so it gets a fresh instance rather than the old
    // key's values.
    key((props) => `${props.id}-${props.facet.key}-${facetSourceKey(props.facet)}`),
    path((key) => ['products', 'logs', 'frontend', 'components', 'LogsViewer', 'FacetRail', 'facetValuesLogic', key]),

    connect((props: FacetValuesLogicProps) => ({
        values: [
            logsViewerFiltersLogic({ id: props.id }),
            ['filters', 'utcDateRange', 'queryFilterGroup', 'personId'],
            teamLogic,
            ['currentTeamId'],
        ],
    })),

    actions({
        setFacetSearch: (search: string) => ({ search }),
        // Declared here rather than left to the loader so it carries no payload — the request is
        // built from current values, and typegen would otherwise infer one from the loader's params.
        loadFacetValues: true,
    }),

    reducers({
        facetSearch: [
            '',
            {
                setFacetSearch: (_, { search }) => search,
            },
        ],
    }),

    loaders(({ props, values }) => ({
        facetValues: [
            [] as _LogFacetValueApi[],
            {
                loadFacetValues: async (_, breakpoint) => {
                    await breakpoint(300)
                    if (!values.currentTeamId) {
                        return values.facetValues
                    }
                    const { source } = props.facet
                    const group = values.queryFilterGroup as UniversalFiltersGroup
                    const filterGroup = ((group?.values?.[0] as UniversalFiltersGroup | undefined)?.values ??
                        []) as unknown as _LogPropertyFilterApi[]
                    const target: Partial<_LogsFacetValuesBodyApi> =
                        source.type === 'column'
                            ? { facetField: source.column }
                            : { facetResourceAttribute: source.key }
                    const response = await logsFacetValuesCreate(String(values.currentTeamId), {
                        query: {
                            ...target,
                            dateRange: values.utcDateRange,
                            severityLevels: values.filters.severityLevels ?? [],
                            serviceNames: values.filters.serviceNames ?? [],
                            searchTerm: values.filters.searchTerm || undefined,
                            facetSearch: values.facetSearch || undefined,
                            filterGroup,
                            personId: values.personId,
                        },
                    })
                    // Bail out right after the round-trip: the rail (and this logic) unmounts when the
                    // user collapses it, and returning into a dead store throws rather than being
                    // discarded.
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),

    selectors({
        // Everything that can change this facet's values, minus its own selection.
        scopeSignature: [
            (s) => [
                s.filters,
                s.queryFilterGroup,
                s.personId,
                s.utcDateRange,
                s.currentTeamId,
                (_, p) => p.facet as FacetConfig,
            ],
            (
                filters: LogsViewerFilters,
                queryFilterGroup: UniversalFiltersGroup,
                personId: string | undefined,
                utcDateRange: {
                    date_from: string | null | undefined
                    date_to: string | null | undefined
                    explicitDate: boolean | null | undefined
                },
                currentTeamId: number | null,
                facet: FacetConfig
            ): string =>
                facetScopeSignature(facet, {
                    currentTeamId,
                    utcDateRange,
                    searchTerm: filters.searchTerm,
                    severityLevels: filters.severityLevels,
                    serviceNames: filters.serviceNames,
                    queryFilterGroup,
                    personId,
                }),
        ],
        // One trigger for the one in-flight request: a scope change and a keystroke in this facet's
        // search box supersede each other rather than racing.
        fetchSignature: [
            (s) => [s.scopeSignature, s.facetSearch],
            (scopeSignature: string, facetSearch: string): string => `${scopeSignature}|${facetSearch}`,
        ],
    }),

    subscriptions(({ actions }) => ({
        // Fires with its initial value on mount, so this is also the first fetch.
        fetchSignature: () => actions.loadFacetValues(),
    })),
])
