/**
 * One facet's values + counts, cross-filtered server-side: the results reflect every active filter
 * except this facet's own selection, which the backend strips from the WHERE clause.
 *
 * One instance per facet, so each holds its own search and loading state. Most attribute facets
 * don't fetch here at all: they read their slice of facetValuesBatchLogic's shared query, which
 * answers the whole rail at once. This path is for the rest — column facets, a facet being
 * searched, and a resource-attribute facet with a filter on its own key.
 *
 * When it does fetch, it fetches on `fetchSignature` — the scope with this facet's own filters
 * removed, plus its type-ahead — so clicking a value here re-scopes the *other* facets and leaves
 * this list alone, and a facet whose section is collapsed doesn't fetch until it's expanded.
 */
export const facetValuesLogic = kea<facetValuesLogicType>([
    props({} as FacetValuesLogicProps),
    // The resolved source key is part of the key: when alias resolution moves a facet onto another
    // attribute spelling, that's a different query, so it gets a fresh instance rather than the old
    // key's values.
    key((props) => `${props.id}-${props.facet.key}-${facetSourceKey(props.facet)}`),
    path((key) => ['products', 'logs', 'frontend', 'components', 'LogsViewer', 'FacetRail', 'facetValuesLogic', key]),

    connect((props: FacetValuesLogicProps) => ({
        values: [
            logsViewerFiltersLogic({ id: props.id }),
            ['filters', 'utcDateRange', 'queryFilterGroup', 'personId', 'sessionId', 'facetRefreshCounter'],
            teamLogic,
            ['currentTeamId'],
            facetRailLogic({ id: props.id }),
            ['collapsedFacets'],
            facetValuesBatchLogic({ id: props.id }),
            ['store as batchStore', 'storeLoading as batchLoading', 'loadFailed as batchFailed'],
        ],
    })),

    actions({
        setFacetSearch: (search: string) => ({ search }),
        // Declared here rather than left to the loader: the request is built from current values,
        // and the signature payload is only there for the reducer below to record.
        loadFacetValues: (signature: string) => ({ signature }),
        clearFetchedSignature: true,
    }),

    reducers({
        facetSearch: [
            '',
            {
                setFacetSearch: (_, { search }) => search,
            },
        ],
        // The signature the values in the store were fetched for. Set when the request goes out, not
        // when it lands, so an overlapping trigger (e.g. expanding the facet mid-flight) doesn't
        // restart the same request. Cleared on failure, and when collapsing abandons an in-flight
        // load, so the next trigger retries rather than trusting values that never arrived.
        fetchedSignature: [
            null as string | null,
            {
                loadFacetValues: (_, { signature }) => signature,
                loadFacetValuesFailure: () => null,
                clearFetchedSignature: () => null,
            },
        ],
    }),

    loaders(({ props, values }) => ({
        facetValues: [
            [] as _LogFacetValueApi[],
            {
                loadFacetValues: async (_, breakpoint) => {
                    await breakpoint(300)
                    // Collapsed while this was still debouncing: nobody can see the list, so drop the
                    // request. clearFetchedSignature has already run, so expanding refetches.
                    if (values.collapsed || !values.currentTeamId) {
                        return values.facetValues
                    }
                    const { source } = props.facet
                    const group = values.queryFilterGroup as UniversalFiltersGroup
                    const filterGroup = ((group?.values?.[0] as UniversalFiltersGroup | undefined)?.values ??
                        []) as unknown as _LogPropertyFilterApi[]
                    const target: Partial<_LogsFacetValuesBodyApi> =
                        source.type === 'column'
                            ? { facetField: source.column }
                            : source.type === 'attribute'
                              ? { facetAttribute: source.key }
                              : { facetResourceAttribute: source.key }
                    const response = await logsFacetValuesCreate(String(values.currentTeamId), {
                        query: {
                            ...target,
                            dateRange: values.utcDateRange,
                            searchTerm: values.filters.searchTerm || undefined,
                            facetSearch: values.facetSearch || undefined,
                            filterGroup,
                            personId: values.personId,
                            sessionId: values.sessionId,
                        },
                    })
                    // Bail out right after the round-trip: the rail (and this logic) unmounts when the
                    // user collapses it, and returning into a dead store throws rather than being
                    // discarded.
                    breakpoint()
                    // One grouped shape whichever target was asked for; a single-target request
                    // comes back as a one-entry list under the field it asked on.
                    if (source.type === 'column') {
                        return response.results.facetField
                    }
                    const entries =
                        source.type === 'attribute'
                            ? response.results.facetAttributes
                            : response.results.facetResourceAttributes
                    return entries[0]?.values ?? []
                },
            },
        ],
    })),

    selectors({
        collapsed: [
            (s) => [s.collapsedFacets, (_, p) => p.facet],
            (collapsedFacets: string[], facet: FacetConfig): boolean => collapsedFacets.includes(facet.key),
        ],
        // Whether the rail's shared query answers this facet, so it doesn't fetch for itself.
        // Decided from this facet's own config, not from the coordinator's demand set: that set is
        // empty until the presence probe lands, and a facet reading it would fire exactly the
        // request batching exists to avoid. The two agree because the coordinator derives its set
        // from visibleFacets and RailFacet only ever renders facets from visibleFacets.
        isBatched: [
            (s) => [s.facetSearch, s.queryFilterGroup, (_, p) => p.facet],
            (facetSearch: string, queryFilterGroup: UniversalFiltersGroup, facet: FacetConfig): boolean =>
                !facetSearch && isBatchableFacet(facet, queryFilterGroup),
        ],
        // `undefined` until the batch has covered this facet, which is what tells the difference
        // between "no values" and "not fetched yet".
        batchValues: [
            (s) => [s.batchStore, (_, p) => p.facet],
            (batchStore: Record<string, _LogFacetValueApi[]>, facet: FacetConfig): _LogFacetValueApi[] | undefined => {
                const target = facetAttributeTarget(facet)
                return target ? batchStore[facetTargetKey(target)] : undefined
            },
        ],
        // Falls back to the batch's slice only while this facet's own request is in flight, so a
        // facet that just left the batch — by being searched, or by taking a filter of its own —
        // keeps values on screen instead of blanking to a skeleton. Once the request settles its own
        // values win, empty or not: a search matching nothing, or a request that failed, must not
        // show the batch's unfiltered list as if it were the answer.
        displayedValues: [
            (s) => [s.isBatched, s.batchValues, s.facetValues, s.facetValuesLoading],
            (
                isBatched: boolean,
                batchValues: _LogFacetValueApi[] | undefined,
                facetValues: _LogFacetValueApi[],
                facetValuesLoading: boolean
            ): _LogFacetValueApi[] => {
                if (isBatched) {
                    return batchValues ?? []
                }
                if (!facetValuesLoading) {
                    return facetValues
                }
                return facetValues.length > 0 ? facetValues : (batchValues ?? [])
            },
        ],
        // A batched facet with no slice yet is still loading, even before the coordinator's
        // debounce has fired its request — otherwise the rail flashes "no values" on mount. Unless
        // the batch failed, in which case there is nothing more coming and the facet shows its
        // empty state rather than a skeleton that never resolves.
        valuesLoading: [
            (s) => [s.isBatched, s.batchLoading, s.batchValues, s.batchFailed, s.facetValuesLoading],
            (
                isBatched: boolean,
                batchLoading: boolean,
                batchValues: _LogFacetValueApi[] | undefined,
                batchFailed: boolean,
                facetValuesLoading: boolean
            ): boolean =>
                isBatched ? batchLoading || (batchValues === undefined && !batchFailed) : facetValuesLoading,
        ],
        // Everything that can change this facet's values, minus its own selection.
        scopeSignature: [
            (s) => [
                s.filters,
                s.queryFilterGroup,
                s.personId,
                s.sessionId,
                s.utcDateRange,
                s.currentTeamId,
                s.facetRefreshCounter,
                (_, p) => p.facet as FacetConfig,
            ],
            (
                filters: LogsViewerFilters,
                queryFilterGroup: UniversalFiltersGroup,
                personId: string | undefined,
                sessionId: string | undefined,
                utcDateRange: {
                    date_from: string | null | undefined
                    date_to: string | null | undefined
                    explicitDate: boolean | null | undefined
                },
                currentTeamId: number | null,
                facetRefreshCounter: number,
                facet: FacetConfig
            ): string =>
                `${facetScopeSignature(facet, {
                    currentTeamId,
                    utcDateRange,
                    searchTerm: filters.searchTerm,
                    queryFilterGroup,
                    personId,
                    sessionId,
                })}|r${facetRefreshCounter}`,
        ],
        // One trigger for the one in-flight request: a scope change and a keystroke in this facet's
        // search box supersede each other rather than racing.
        fetchSignature: [
            (s) => [s.scopeSignature, s.facetSearch],
            (scopeSignature: string, facetSearch: string): string => `${scopeSignature}|${facetSearch}`,
        ],
    }),

    subscriptions(({ actions, values }) => {
        // Subscriptions fire with their initial value, so this is also the mount fetch.
        const loadIfStale = (): void => {
            if (values.isBatched || values.collapsed || values.fetchSignature === values.fetchedSignature) {
                return
            }
            actions.loadFacetValues(values.fetchSignature)
        }
        return {
            fetchSignature: loadIfStale,
            isBatched: (isBatched: boolean, previous: boolean | undefined) => {
                // Only a genuine handover, not the initial fire every subscription makes — acting on
                // that would clear the signature of the fetch just started and immediately redo it.
                // Collapsing also drops a facet from the batch, but there's nothing to show and
                // nothing worth fetching until it's expanded again.
                if (isBatched || previous === undefined || values.collapsed) {
                    return
                }
                // Leaving the batch. The shared slice was fetched without this facet's own filter
                // excluded, and fetchedSignature belongs to fetches this facet made itself, so
                // neither vouches for what to show now — drop it and fetch. Clicking a value in a
                // facet doesn't move its own fetchSignature, so nothing else would trigger this.
                actions.clearFetchedSignature()
                loadIfStale()
            },
            collapsed: (collapsed: boolean) => {
                if (collapsed) {
                    // The loader drops a still-debouncing load on collapse, so forget the signature it
                    // recorded — otherwise expanding would trust values that never arrived. Only when
                    // one is in flight: settled values stay valid for their signature.
                    if (values.facetValuesLoading) {
                        actions.clearFetchedSignature()
                    }
                    return
                }
                // Expanding fetches what it missed while collapsed — and nothing if the scope hasn't
                // moved since.
                loadIfStale()
            },
        }
    }),
])
