/**
 * The rail's shared fetch for every attribute facet that can use one.
 *
 * Attribute facets all read the same rollup with the same WHERE, so they answer in a single query
 * instead of one request each — which matters because facets are expanded by default and the whole
 * rail refetches on every filter or date change. One instance per rail, not per facet:
 * facetValuesLogic stays keyed and reads its slice from here (see `isBatched` there), which keeps
 * the dependency one-directional.
 *
 * A facet that needs its own filter excluded, or is being searched, isn't in the batch and fetches
 * for itself. Column facets are never in it — they read the logs table, not the rollup.
 */
export const facetValuesBatchLogic = kea<facetValuesBatchLogicType>([
    props({} as FacetValuesBatchLogicProps),
    key((props) => props.id),
    path((key) => [
        'products',
        'logs',
        'frontend',
        'components',
        'LogsViewer',
        'FacetRail',
        'facetValuesBatchLogic',
        key,
    ]),

    connect((props: FacetValuesBatchLogicProps) => ({
        values: [
            logsViewerFiltersLogic({ id: props.id }),
            ['filters', 'utcDateRange', 'queryFilterGroup', 'personId', 'facetRefreshCounter'],
            teamLogic,
            ['currentTeamId'],
            facetPresenceLogic({ id: props.id }),
            ['visibleFacets', 'presentResourceKeysLoading'],
            facetRailLogic({ id: props.id }),
            ['collapsedFacets'],
        ],
    })),

    actions({
        // The scope and targets are carried on the action so the reducers can record what the
        // response that lands actually covers, rather than whatever is current by then.
        loadBatch: (scope: string, targets: FacetAttributeTarget[]) => ({ scope, targets }),
    }),

    reducers({
        // Recorded on success, not on request: a breakpoint cancellation dispatches neither success
        // nor failure, so marking at request time would leave keys looking fetched with values that
        // never arrived, and nothing to roll them back.
        fetchedScope: [
            null as string | null,
            {
                loadBatchSuccess: (state, { payload }) => payload?.scope ?? state,
            },
        ],
        fetchedKeys: [
            [] as string[],
            {
                loadBatchSuccess: (state, { payload }) => (payload ? payload.targets.map(facetTargetKey) : state),
            },
        ],
        // Without this a failed load looks exactly like one that hasn't happened yet, and every
        // facet waiting on the batch would show a skeleton for as long as the rail is open.
        loadFailed: [
            false,
            {
                loadBatch: () => false,
                loadBatchSuccess: () => false,
                loadBatchFailure: () => true,
            },
        ],
    }),

    loaders(({ values }) => ({
        store: [
            {} as Record<string, _LogFacetValueApi[]>,
            {
                loadBatch: async ({ targets }, breakpoint) => {
                    await breakpoint(300)
                    if (!values.currentTeamId || targets.length === 0) {
                        return values.store
                    }
                    const group = values.queryFilterGroup as UniversalFiltersGroup
                    const filterGroup = ((group?.values?.[0] as UniversalFiltersGroup | undefined)?.values ??
                        []) as unknown as _LogPropertyFilterApi[]
                    // The endpoint caps keys per request, and a user can pin more custom facets than
                    // that — so chunk rather than truncate, which would leave the overflow facets
                    // with nothing, or send them all and have every request rejected.
                    const chunks: FacetAttributeTarget[][] = []
                    for (let i = 0; i < targets.length; i += MAX_KEYS_PER_BATCH) {
                        chunks.push(targets.slice(i, i + MAX_KEYS_PER_BATCH))
                    }
                    const responses = await Promise.all(
                        chunks.map((chunk) =>
                            logsFacetValuesBatchCreate(String(values.currentTeamId), {
                                query: {
                                    facetResourceAttributes: chunk
                                        .filter((t) => t.attributeType === 'resource')
                                        .map((t) => t.attributeKey),
                                    facetAttributes: chunk
                                        .filter((t) => t.attributeType === 'log')
                                        .map((t) => t.attributeKey),
                                    dateRange: values.utcDateRange,
                                    searchTerm: values.filters.searchTerm || undefined,
                                    filterGroup,
                                    personId: values.personId,
                                },
                            })
                        )
                    )
                    // Bail out right after the round-trip: the rail unmounts when the user collapses
                    // it, and returning into a dead store throws rather than being discarded.
                    breakpoint()
                    // Entries the response didn't cover keep their previous values rather than being
                    // dropped, so a facet that leaves the batch — by being searched, or by taking a
                    // filter of its own — still has something to render while it fetches for itself.
                    const next = { ...values.store }
                    for (const response of responses) {
                        for (const entry of response.results.facetResourceAttributes) {
                            next[facetTargetKey({ attributeType: 'resource', attributeKey: entry.key })] = entry.values
                        }
                        for (const entry of response.results.facetAttributes) {
                            next[facetTargetKey({ attributeType: 'log', attributeKey: entry.key })] = entry.values
                        }
                    }
                    return next
                },
            },
        ],
    })),

    selectors({
        // Every facet that can share the batch and is on screen. A searching facet stays in here:
        // one more key costs nothing, and leaving it in means clearing the search costs no request.
        demandTargets: [
            (s) => [s.visibleFacets, s.collapsedFacets, s.queryFilterGroup],
            (
                visibleFacets: FacetConfig[],
                collapsedFacets: string[],
                queryFilterGroup: UniversalFiltersGroup
            ): FacetAttributeTarget[] => {
                const targets: FacetAttributeTarget[] = []
                const seen = new Set<string>()
                for (const facet of visibleFacets) {
                    if (collapsedFacets.includes(facet.key) || !isBatchableFacet(facet, queryFilterGroup)) {
                        continue
                    }
                    const target = facetAttributeTarget(facet)
                    if (!target || seen.has(facetTargetKey(target))) {
                        continue
                    }
                    seen.add(facetTargetKey(target))
                    targets.push(target)
                }
                return targets
            },
        ],
        // The refresh counter rides along so a manual re-run refetches the batch, the same way it
        // refetches a facet that fetches for itself. Without it the rail's shared values would sit
        // unchanged on re-run, which is most of the rail.
        scopeSignature: [
            (s) => [s.filters, s.queryFilterGroup, s.personId, s.utcDateRange, s.currentTeamId, s.facetRefreshCounter],
            (
                filters: LogsViewerFilters,
                queryFilterGroup: UniversalFiltersGroup,
                personId: string | undefined,
                utcDateRange: {
                    date_from: string | null | undefined
                    date_to: string | null | undefined
                    explicitDate: boolean | null | undefined
                },
                currentTeamId: number | null,
                facetRefreshCounter: number
            ): string =>
                `${batchScopeSignature({
                    currentTeamId,
                    utcDateRange,
                    searchTerm: filters.searchTerm,
                    queryFilterGroup,
                    personId,
                })}|r${facetRefreshCounter}`,
        ],
    }),

    subscriptions(({ actions, values }) => {
        // A listener would need every action across three upstream logics; the trigger is a derived
        // value, so subscribe to it. Subscriptions fire with their initial value, so this is also
        // the mount fetch.
        const loadIfStale = (): void => {
            // Curated resource-attribute facets only become visible once the presence probe lands.
            // Firing before then would batch whatever is visible so far and then batch again —
            // two requests where the point of this logic is one.
            if (values.presentResourceKeysLoading) {
                return
            }
            const stale =
                values.scopeSignature !== values.fetchedScope ||
                values.demandTargets.some((target) => !values.fetchedKeys.includes(facetTargetKey(target)))
            if (!stale || values.demandTargets.length === 0) {
                return
            }
            actions.loadBatch(values.scopeSignature, values.demandTargets)
        }
        return {
            scopeSignature: loadIfStale,
            // Collapsing shrinks the demand set, which is already covered — only expanding fetches.
            demandTargets: loadIfStale,
            presentResourceKeysLoading: loadIfStale,
        }
    }),
])
