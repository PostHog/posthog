export type facetPresenceLogicType = MakeLogicType<
    facetPresenceLogicValues,
    facetPresenceLogicActions,
    FacetPresenceLogicProps,
    facetPresenceLogicMeta
>

/**
 * Which facets the rail renders. The curated list in FACETS is config, not data: a resource-attribute
 * facet only earns a slot if the tenant emits its key (or an older spelling of it), so this probes the
 * emitted keys once on mount and resolves the list against them. Values and counts are fetched per
 * facet, by facetValuesLogic.
 */
export const facetPresenceLogic = kea<facetPresenceLogicType>([
    props({ id: 'default' } as FacetPresenceLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'logs', 'frontend', 'components', 'LogsViewer', 'FacetRail', 'facetPresenceLogic', key]),

    connect((props: FacetPresenceLogicProps) => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            customFacetsLogic,
            ['customFacets'],
            logsViewerFiltersLogic({ id: props.id }),
            ['utcDateRange'],
        ],
        actions: [logsViewerFiltersLogic({ id: props.id }), ['bumpFacetRefresh']],
    })),

    loaders(({ values }) => ({
        presentResourceKeys: [
            [] as string[],
            {
                // Which resource attribute keys the tenant emits — gates which curated facets render.
                loadPresentResourceKeys: async () => {
                    if (!values.currentTeamId) {
                        return []
                    }
                    const response = await logsAttributesRetrieve(String(values.currentTeamId), {
                        attribute_type: 'resource',
                        keys: PRESENCE_KEYS.join(','),
                        limit: PRESENCE_KEYS.length,
                        ...values.presenceWindow,
                    })
                    return response.results.map((r) => r.name)
                },
            },
        ],
    })),

    selectors({
        presenceWindow: [
            (s) => [s.utcDateRange],
            (utcDateRange: {
                date_from: string | null | undefined
                date_to: string | null | undefined
                explicitDate: boolean | null | undefined
            }) => presenceProbeWindow(utcDateRange),
        ],
        // Use a string so an equal window object does not start another probe.
        presenceWindowSignature: [
            (s) => [s.presenceWindow],
            (
                presenceWindow: {
                    date_from: string
                    date_to?: string
                } | null
            ) => JSON.stringify(presenceWindow),
        ],
        // Column facets always render; resource-attribute facets only when the tenant emits the key (or one
        // of its aliases, which resolution rewrites the facet onto). Custom facets skip that presence gate
        // entirely — the user picked them from a live taxonomic list, so they're known to exist already —
        // and render last, after every curated facet.
        // Intermediate so curated facet identities stay stable across custom-facet changes — a fresh
        // alias-resolved FacetConfig would re-render every virtualized value row (see RailFacet).
        resolvedFacets: [
            (s) => [s.presentResourceKeys],
            (presentResourceKeys: string[]): FacetConfig[] => resolveFacets(FACETS, presentResourceKeys),
        ],
        visibleFacets: [
            (s) => [s.resolvedFacets, s.customFacets],
            (resolvedFacets: FacetConfig[], customFacets: FacetConfig[]): FacetConfig[] => [
                ...resolvedFacets,
                ...customFacets,
            ],
        ],
    }),

    listeners(({ actions }) => ({
        bumpFacetRefresh: () => actions.loadPresentResourceKeys(),
    })),

    subscriptions(({ actions }) => ({
        // A change between recent selections does not change the signature or start a new probe.
        presenceWindowSignature: (signature: string, previous: string | undefined) => {
            if (previous !== undefined && signature !== previous) {
                actions.loadPresentResourceKeys()
            }
        },
    })),

    events(({ actions }) => ({
        afterMount: () => actions.loadPresentResourceKeys(),
    })),
])
