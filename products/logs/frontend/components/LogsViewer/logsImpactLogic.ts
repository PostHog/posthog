import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { UniversalFiltersGroup } from '~/types'

import { logsViewerDataLogic } from 'products/logs/frontend/components/LogsViewer/data/logsViewerDataLogic'
import { logsViewerFiltersLogic } from 'products/logs/frontend/components/LogsViewer/Filters/logsViewerFiltersLogic'
import { logsImpactCreate } from 'products/logs/frontend/generated/api'
import type { _LogsCountBodyApi, _LogsImpactResponseApi } from 'products/logs/frontend/generated/api.schemas'

import type { LogsViewerFilters } from './config/types'

export interface LogsImpactLogicProps {
    id: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsImpactLogicValues {
    filters: LogsViewerFilters // logsViewerFiltersLogic
    personId: string | undefined // logsViewerFiltersLogic
    queryFilterGroup: UniversalFiltersGroup // logsViewerFiltersLogic
    utcDateRange: {
        date_from: string | null | undefined
        date_to: string | null | undefined
        explicitDate: boolean | null | undefined
    } // logsViewerFiltersLogic
    currentTeamId: number | null // teamLogic
    impact: _LogsImpactResponseApi | null
    impactLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsImpactLogicActions {
    fetchSparkline: () => any // logsViewerDataLogic
    loadImpact: (_: any) => any
    loadImpactFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadImpactSuccess: (
        impact: _LogsImpactResponseApi,
        payload?: any
    ) => {
        impact: _LogsImpactResponseApi
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsImpactLogicMeta {
    key: string
}

export type logsImpactLogicType = MakeLogicType<
    logsImpactLogicValues,
    logsImpactLogicActions,
    LogsImpactLogicProps,
    logsImpactLogicMeta
>

export const logsImpactLogic = kea<logsImpactLogicType>([
    props({} as LogsImpactLogicProps),
    key(({ id }) => id),
    path((key) => ['products', 'logs', 'frontend', 'components', 'LogsViewer', 'logsImpactLogic', key]),
    connect(({ id }: LogsImpactLogicProps) => ({
        values: [
            logsViewerFiltersLogic({ id }),
            ['utcDateRange', 'queryFilterGroup', 'filters', 'personId'],
            teamLogic,
            ['currentTeamId'],
        ],
        actions: [logsViewerDataLogic({ id }), ['fetchSparkline']],
    })),
    loaders(({ values }) => ({
        impact: [
            null as _LogsImpactResponseApi | null,
            {
                loadImpact: async (_, breakpoint) => {
                    await breakpoint(300)
                    // The serializer models `filterGroup` as a flat filter list, but the endpoint
                    // also accepts the nested group the viewer holds (the view normalizes both),
                    // so the request body needs a cast the generated type can't express.
                    const query = {
                        dateRange: values.utcDateRange,
                        searchTerm: values.filters.searchTerm,
                        filterGroup: values.queryFilterGroup,
                    } as unknown as _LogsCountBodyApi
                    const response = await logsImpactCreate(String(values.currentTeamId), { query })
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    listeners(({ actions }) => ({
        // The data logic dispatches fetchSparkline exactly once per executed query
        // (after its own debounce), so it doubles as the "query changed" signal
        // without re-implementing the debounce here.
        fetchSparkline: () => actions.loadImpact({}),
    })),
    afterMount(({ actions }) => {
        actions.loadImpact({})
    }),
])
