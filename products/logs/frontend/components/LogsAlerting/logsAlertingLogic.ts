import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import { subscriptions } from 'kea-subscriptions'

import { lemonToast } from '@posthog/lemon-ui'

import { dayjs } from 'lib/dayjs'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import {
    logsAlertsDestroy,
    logsAlertsList,
    logsAlertsPartialUpdate,
    logsAlertsResetCreate,
} from 'products/logs/frontend/generated/api'
import { LogsAlertConfigurationApi } from 'products/logs/frontend/generated/api.schemas'

import { alertFiltersForPreEnableCheck, dispatchPreEnableCheck, runPreEnableChecks } from './logsAlertUtils'

const ALERT_POLL_INTERVAL_MS = 30_000

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAlertingLogicValues {
    currentTeamId: number | null // teamLogic
    alerts: LogsAlertConfigurationApi[]
    alertsLoading: boolean
    createdByFilter: string | null
    isCreateAlertModalOpen: boolean
    resettingAlertIds: Set<string>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAlertingLogicActions {
    closeCreateAlertModal: () => {
        value: true
    }
    deleteAlert: (id: string) => {
        id: string
    }
    loadAlerts: (_?: any) => any
    loadAlertsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAlertsSuccess: (
        alerts: LogsAlertConfigurationApi[],
        payload?: any
    ) => {
        alerts: LogsAlertConfigurationApi[]
        payload?: any
    }
    openCreateAlertModal: () => {
        value: true
    }
    resetAlert: (id: string) => {
        id: string
    }
    setCreatedByFilter: (createdByFilter: string | null) => {
        createdByFilter: string | null
    }
    setResettingAlertId: (
        id: string,
        resetting: boolean
    ) => {
        id: string
        resetting: boolean
    }
    snoozeAlert: (
        alertId: string,
        durationMinutes: number
    ) => {
        alertId: string
        durationMinutes: number
    }
    toggleAlertEnabled: (alert: LogsAlertConfigurationApi) => {
        alert: LogsAlertConfigurationApi
    }
    unsnoozeAlert: (alertId: string) => {
        alertId: string
    }
}

export type logsAlertingLogicType = MakeLogicType<logsAlertingLogicValues, logsAlertingLogicActions>

export const logsAlertingLogic = kea<logsAlertingLogicType>([
    path(['products', 'logs', 'frontend', 'components', 'LogsAlerting', 'logsAlertingLogic']),

    connect({
        values: [teamLogic, ['currentTeamId']],
    }),

    actions({
        setCreatedByFilter: (createdByFilter: string | null) => ({ createdByFilter }),
        deleteAlert: (id: string) => ({ id }),
        toggleAlertEnabled: (alert: LogsAlertConfigurationApi) => ({ alert }),
        resetAlert: (id: string) => ({ id }),
        setResettingAlertId: (id: string, resetting: boolean) => ({ id, resetting }),
        snoozeAlert: (alertId: string, durationMinutes: number) => ({ alertId, durationMinutes }),
        unsnoozeAlert: (alertId: string) => ({ alertId }),
        openCreateAlertModal: true,
        closeCreateAlertModal: true,
    }),

    reducers({
        createdByFilter: [
            null as string | null,
            {
                setCreatedByFilter: (_, { createdByFilter }) => createdByFilter,
            },
        ],
        resettingAlertIds: [
            new Set<string>(),
            {
                setResettingAlertId: (state, { id, resetting }) =>
                    resetting ? new Set([...state, id]) : new Set([...state].filter((x) => x !== id)),
            },
        ],
        isCreateAlertModalOpen: [
            false,
            {
                openCreateAlertModal: () => true,
                closeCreateAlertModal: () => false,
            },
        ],
    }),

    loaders(({ values }) => ({
        alerts: [
            [] as LogsAlertConfigurationApi[],
            {
                loadAlerts: async (_ = null, breakpoint) => {
                    const projectId = String(values.currentTeamId)
                    const response = await logsAlertsList(projectId, {
                        limit: 500,
                        ...(values.createdByFilter ? { created_by: values.createdByFilter } : {}),
                    })
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),

    listeners(({ actions, values }) => ({
        setCreatedByFilter: () => actions.loadAlerts(),
        deleteAlert: async ({ id }) => {
            const projectId = String(values.currentTeamId)
            try {
                await logsAlertsDestroy(projectId, id)
                lemonToast.success('Alert deleted')
                actions.loadAlerts()
            } catch {
                lemonToast.error('Failed to delete alert')
            }
        },
        toggleAlertEnabled: ({ alert }) => {
            const isEnabling = !(alert.enabled ?? true)
            const projectId = String(values.currentTeamId)

            const performToggle = async (): Promise<void> => {
                try {
                    await logsAlertsPartialUpdate(projectId, alert.id, {
                        enabled: !(alert.enabled ?? true),
                    })
                    actions.loadAlerts()
                } catch {
                    lemonToast.error('Failed to update alert')
                }
            }

            if (!isEnabling) {
                void performToggle()
                return
            }

            dispatchPreEnableCheck(runPreEnableChecks(alert, alertFiltersForPreEnableCheck(alert)), {
                onConfirm: () => void performToggle(),
                onConfigureNotifications: () => router.actions.push(urls.logsAlertDetail(alert.id, 'notifications')),
            })
        },
        resetAlert: async ({ id }) => {
            const projectId = String(values.currentTeamId)
            actions.setResettingAlertId(id, true)
            try {
                await logsAlertsResetCreate(projectId, id)
                lemonToast.success('Alert reset — next check will run shortly.')
                actions.loadAlerts()
            } catch {
                lemonToast.error('Failed to reset alert')
            } finally {
                actions.setResettingAlertId(id, false)
            }
        },
        snoozeAlert: async ({ alertId, durationMinutes }) => {
            const projectId = String(values.currentTeamId)
            const snoozeUntil = dayjs().add(durationMinutes, 'minute').toISOString()
            try {
                await logsAlertsPartialUpdate(projectId, alertId, { snooze_until: snoozeUntil })
                lemonToast.success('Alert snoozed')
                actions.loadAlerts()
            } catch {
                lemonToast.error('Failed to snooze alert')
            }
        },
        unsnoozeAlert: async ({ alertId }) => {
            const projectId = String(values.currentTeamId)
            try {
                await logsAlertsPartialUpdate(projectId, alertId, { snooze_until: null })
                lemonToast.success('Alert unsnoozed')
                actions.loadAlerts()
            } catch {
                lemonToast.error('Failed to unsnooze alert')
            }
        },
    })),

    subscriptions(({ actions }) => ({
        currentTeamId: (currentTeamId, previousTeamId) => {
            if (previousTeamId !== null && currentTeamId !== previousTeamId) {
                actions.setCreatedByFilter(null)
            }
        },
    })),

    afterMount(({ actions, cache }) => {
        actions.loadAlerts()
        cache.disposables.add(() => {
            const intervalId = window.setInterval(() => {
                actions.loadAlerts()
            }, ALERT_POLL_INTERVAL_MS)
            return () => clearInterval(intervalId)
        }, 'pollAlerts')
    }),
])
