export const logsAlertNotificationLogic = kea<logsAlertNotificationLogicType>([
    path(['products', 'logs', 'frontend', 'components', 'LogsAlerting', 'logsAlertNotificationLogic']),
    props({} as LogsAlertNotificationLogicProps),
    key(({ alertId }) => alertId ?? 'new'),

    connect({
        values: [projectLogic, ['currentProjectId'], integrationsLogic, ['integrationsLoading', 'slackIntegrations']],
        actions: [integrationsLogic, ['loadIntegrations', 'loadIntegrationsFailure', 'loadIntegrationsSuccess']],
    }),

    actions({
        addPendingNotification: (notification: PendingLogsAlertNotification) => ({ notification }),
        addSelectedNotification: true,
        removePendingNotification: (index: number) => ({ index }),
        clearPendingNotifications: true,
        setPendingNotifications: (notifications: PendingLogsAlertNotification[]) => ({ notifications }),
        deleteExistingDestination: (group: LogsAlertDestinationGroup) => ({ group }),
        createPendingHogFunctions: (alertId: string) => ({ alertId }),
        destinationsChanged: true,
        setSelectedType: (selectedType: LogsAlertNotificationType) => ({ selectedType }),
        setSlackChannelValue: (slackChannelValue: string | null) => ({ slackChannelValue }),
        setWebhookUrl: (webhookUrl: string) => ({ webhookUrl }),
        setPagerDutyRoutingKey: (pagerDutyRoutingKey: string) => ({ pagerDutyRoutingKey }),
        setPagerDutySeverity: (pagerDutySeverity: AlertPagerDutySeverity) => ({ pagerDutySeverity }),
        setPagerDutyRegion: (pagerDutyRegion: AlertPagerDutyRegion) => ({ pagerDutyRegion }),
    }),

    reducers({
        pendingNotifications: [
            [] as PendingLogsAlertNotification[],
            {
                addPendingNotification: (state, { notification }) => [...state, notification],
                removePendingNotification: (state, { index }) => state.filter((_, i) => i !== index),
                clearPendingNotifications: () => [],
                setPendingNotifications: (_, { notifications }) => notifications,
            },
        ],
        integrationsFailed: [
            false,
            {
                loadIntegrations: () => false,
                loadIntegrationsFailure: () => true,
                loadIntegrationsSuccess: () => false,
            },
        ],
        slackChannelValue: [
            null as string | null,
            {
                setSlackChannelValue: (_, { slackChannelValue }) => slackChannelValue,
            },
        ],
        webhookUrl: [
            '' as string,
            {
                setWebhookUrl: (_, { webhookUrl }) => webhookUrl,
            },
        ],
        pagerDutyRoutingKey: [
            '' as string,
            {
                setPagerDutyRoutingKey: (_, { pagerDutyRoutingKey }) => pagerDutyRoutingKey,
            },
        ],
        pagerDutySeverity: [
            'critical' as AlertPagerDutySeverity,
            {
                setPagerDutySeverity: (_, { pagerDutySeverity }) => pagerDutySeverity,
            },
        ],
        pagerDutyRegion: [
            'us' as AlertPagerDutyRegion,
            {
                setPagerDutyRegion: (_, { pagerDutyRegion }) => pagerDutyRegion,
            },
        ],
        selectedType: [
            LOGS_ALERT_NOTIFICATION_TYPE_SLACK as LogsAlertNotificationType,
            {
                setSelectedType: (_, { selectedType }) => selectedType,
            },
        ],
    }),

    loaders(({ props }) => ({
        existingHogFunctions: [
            [] as HogFunctionType[],
            {
                loadExistingHogFunctions: async (alertId?: string) => {
                    const id = alertId ?? props.alertId
                    if (!id) {
                        return []
                    }
                    const response = await api.hogFunctions.list({
                        types: ['internal_destination'],
                        filter_groups: [buildLogsAlertFilterConfig(id)],
                        full: true,
                    })
                    return response.results
                },
            },
        ],
    })),

    selectors({
        firstSlackIntegration: [
            (s) => [s.slackIntegrations],
            (slackIntegrations: IntegrationType[] | undefined): IntegrationType | undefined => slackIntegrations?.[0],
        ],
        urlInput: [
            (s) => [s.selectedType],
            (selectedType: LogsAlertNotificationType): AlertNotificationUrlInput | undefined => {
                if (selectedType === LOGS_ALERT_NOTIFICATION_TYPE_TEAMS) {
                    return {
                        placeholder: 'https://prod-00.westus.logic.azure.com:443/workflows/...',
                        helpText:
                            'Paste the URL from a Teams "Workflows" (Power Automate) or incoming webhook connector. We send a formatted Adaptive Card to it.',
                    }
                }
                if (selectedType === LOGS_ALERT_NOTIFICATION_TYPE_WEBHOOK) {
                    return { placeholder: 'https://example.com/webhook' }
                }
                return undefined
            },
        ],
        addDisabledReason: [
            (s) => [s.selectedType, s.firstSlackIntegration, s.slackChannelValue, s.webhookUrl, s.pagerDutyRoutingKey],
            (
                selectedType: LogsAlertNotificationType,
                firstSlackIntegration: IntegrationType | undefined,
                slackChannelValue: string | null,
                webhookUrl: string,
                pagerDutyRoutingKey: string
            ): string | undefined => {
                if (selectedType === LOGS_ALERT_NOTIFICATION_TYPE_PAGERDUTY) {
                    if (!pagerDutyRoutingKey.trim()) {
                        return 'Enter the PagerDuty integration key'
                    }
                    return PAGERDUTY_ROUTING_KEY_PATTERN.test(pagerDutyRoutingKey.trim())
                        ? undefined
                        : 'The integration key is 32 letters and digits'
                }
                if (selectedType !== LOGS_ALERT_NOTIFICATION_TYPE_SLACK) {
                    return webhookUrl ? undefined : 'Enter a webhook URL'
                }
                if (!firstSlackIntegration) {
                    return 'Connect Slack first'
                }
                return slackChannelValue ? undefined : 'Select a Slack channel'
            },
        ],
        // Channel-name resolution happens in the view — slackChannels lives in a dynamically-keyed logic.
        destinationGroups: [
            (s) => [s.existingHogFunctions],
            (hogFunctions: HogFunctionType[]): LogsAlertDestinationGroup[] =>
                groupLogsAlertDestinations(hogFunctions, () => null),
        ],
    }),

    listeners(({ actions, values, props }) => ({
        addSelectedNotification: () => {
            if (values.selectedType === LOGS_ALERT_NOTIFICATION_TYPE_SLACK) {
                if (!values.slackChannelValue || !values.firstSlackIntegration) {
                    return
                }
                const [channelId, channelLabel] = values.slackChannelValue.split('|')
                actions.addPendingNotification({
                    type: LOGS_ALERT_NOTIFICATION_TYPE_SLACK,
                    slackWorkspaceId: values.firstSlackIntegration.id,
                    slackChannelId: channelId,
                    slackChannelName: channelLabel?.replace('#', '') ?? channelId,
                })
                actions.setSlackChannelValue(null)
                return
            }
            if (values.selectedType === LOGS_ALERT_NOTIFICATION_TYPE_PAGERDUTY) {
                const routingKey = values.pagerDutyRoutingKey.trim()
                if (!PAGERDUTY_ROUTING_KEY_PATTERN.test(routingKey)) {
                    return
                }
                actions.addPendingNotification({
                    type: LOGS_ALERT_NOTIFICATION_TYPE_PAGERDUTY,
                    routingKey,
                    severity: values.pagerDutySeverity,
                    region: values.pagerDutyRegion,
                })
                actions.setPagerDutyRoutingKey('')
                return
            }
            if (!values.webhookUrl) {
                return
            }
            actions.addPendingNotification({ type: values.selectedType, webhookUrl: values.webhookUrl })
            actions.setWebhookUrl('')
        },
        addPendingNotification: () => {
            if (props.alertId) {
                actions.createPendingHogFunctions(props.alertId)
            }
        },
        loadIntegrationsSuccess: () => {
            if (!values.firstSlackIntegration) {
                actions.setSelectedType(LOGS_ALERT_NOTIFICATION_TYPE_WEBHOOK)
            }
        },
        deleteExistingDestination: async ({ group }) => {
            if (!props.alertId) {
                return
            }
            try {
                await logsAlertsDestinationsDeleteCreate(String(values.currentProjectId), props.alertId, {
                    hog_function_ids: group.hogFunctions.map((hf) => hf.id),
                })
                lemonToast.success(`Removed ${group.label}`)
                actions.loadExistingHogFunctions()
                actions.destinationsChanged()
            } catch {
                lemonToast.error(`Failed to remove ${group.label}`)
                actions.loadExistingHogFunctions()
            }
        },

        createPendingHogFunctions: async ({ alertId }) => {
            const pending = values.pendingNotifications
            if (pending.length === 0) {
                return
            }

            const projectId = String(values.currentProjectId)
            const results = await Promise.allSettled(
                pending.map((notification) =>
                    logsAlertsDestinationsCreate(projectId, alertId, destinationCreateBody(notification))
                )
            )

            const failedNotifications = pending.filter((_, i) => results[i].status === 'rejected')

            actions.loadExistingHogFunctions(alertId)
            actions.destinationsChanged()

            if (failedNotifications.length > 0) {
                lemonToast.error(
                    `Alert saved, but ${failedNotifications.length} notification(s) failed to create. Reopen the alert to add them again.`
                )
                actions.setPendingNotifications(failedNotifications)
            } else {
                if (pending.length > 0) {
                    lemonToast.success(`${pending.length} notification destination(s) created.`)
                }
                actions.clearPendingNotifications()
            }
        },
    })),

    afterMount(({ actions, props }) => {
        if (props.alertId) {
            actions.loadExistingHogFunctions()
        }
    }),
])
