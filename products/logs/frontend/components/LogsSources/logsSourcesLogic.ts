export const logsSourcesLogic = kea<logsSourcesLogicType>([
    path(['products', 'logs', 'frontend', 'components', 'LogsSources', 'logsSourcesLogic']),

    connect({
        values: [teamLogic, ['currentTeamId']],
    }),

    actions({
        openWizard: true,
        openWizardForSource: (sourceId: string) => ({ sourceId }),
        closeWizard: true,
        setWizardStep: (step: LogsSourceWizardStep) => ({ step }),
        setDraftName: (name: string) => ({ name }),
        setDraftRegion: (region: string) => ({ region }),
        createSource: true,
        sourceCreated: (source: LogsSourceApi) => ({ source }),
        createSourceFinished: true,
        setSourceEnabled: (sourceId: string, enabled: boolean) => ({ sourceId, enabled }),
        setSourceEnabledFinished: true,
        deleteSource: (sourceId: string) => ({ sourceId }),
        sourceDeleted: (sourceId: string) => ({ sourceId }),
        deleteSourceFinished: true,
        setHealthUnavailable: (unavailable: boolean) => ({ unavailable }),
    }),

    loaders(({ actions, values }) => ({
        sources: [
            [] as LogsSourceApi[],
            {
                loadSources: async () => {
                    const page = await logsSourcesList(String(values.currentTeamId))
                    return page.results
                },
            },
        ],
        healthBySourceId: [
            {} as Record<string, LogsSourceHealthApi>,
            {
                loadHealth: async () => {
                    // The waiting step polls this; a failure is shown in the table instead of
                    // toasting on every poll.
                    try {
                        const health = await logsSourcesHealthRetrieve(String(values.currentTeamId))
                        actions.setHealthUnavailable(false)
                        return health.sources
                    } catch {
                        actions.setHealthUnavailable(true)
                        return values.healthBySourceId
                    }
                },
            },
        ],
        setup: [
            null as LogsSourceSetupApi | null,
            {
                loadSetup: async (sourceId: string) => logsSourcesSetupRetrieve(String(values.currentTeamId), sourceId),
            },
        ],
    })),

    reducers({
        sources: {
            setSourceEnabled: (state, { sourceId, enabled }) =>
                state.map((source) => (source.id === sourceId ? { ...source, enabled } : source)),
            sourceDeleted: (state, { sourceId }) => state.filter((source) => source.id !== sourceId),
        },
        sourcesLoadFailed: [
            false,
            {
                loadSources: () => false,
                loadSourcesFailure: () => true,
            },
        ],
        healthUnavailable: [
            false,
            {
                setHealthUnavailable: (_, { unavailable }) => unavailable,
            },
        ],
        setup: {
            openWizard: () => null,
            openWizardForSource: () => null,
        },
        wizardOpen: [
            false,
            {
                openWizard: () => true,
                openWizardForSource: () => true,
                closeWizard: () => false,
            },
        ],
        wizardStep: [
            'details' as LogsSourceWizardStep,
            {
                openWizard: () => 'details',
                openWizardForSource: () => 'connect',
                setWizardStep: (_, { step }) => step,
            },
        ],
        wizardSourceId: [
            null as string | null,
            {
                openWizard: () => null,
                openWizardForSource: (_, { sourceId }) => sourceId,
                sourceCreated: (_, { source }) => source.id,
            },
        ],
        draftName: [
            '',
            {
                openWizard: () => '',
                setDraftName: (_, { name }) => name,
            },
        ],
        draftRegion: [
            'us-east-1',
            {
                setDraftRegion: (_, { region }) => region,
            },
        ],
        createPending: [
            false,
            {
                createSource: () => true,
                createSourceFinished: () => false,
            },
        ],
        togglePendingId: [
            null as string | null,
            {
                setSourceEnabled: (_, { sourceId }) => sourceId,
                setSourceEnabledFinished: () => null,
            },
        ],
        deletePendingId: [
            null as string | null,
            {
                deleteSource: (_, { sourceId }) => sourceId,
                deleteSourceFinished: () => null,
            },
        ],
    }),

    selectors({
        canCreate: [
            (s) => [s.draftName, s.draftRegion, s.createPending],
            (draftName: string, draftRegion: string, createPending: boolean): boolean =>
                draftName.trim().length > 0 && draftRegion.length > 0 && !createPending,
        ],
        wizardSource: [
            (s) => [s.sources, s.wizardSourceId],
            (sources: LogsSourceApi[], wizardSourceId: string | null): LogsSourceApi | null =>
                sources.find((source) => source.id === wizardSourceId) ?? null,
        ],
        wizardHealth: [
            (s) => [s.healthBySourceId, s.wizardSourceId],
            (
                healthBySourceId: Record<string, LogsSourceHealthApi>,
                wizardSourceId: string | null
            ): LogsSourceHealthApi | null => (wizardSourceId ? (healthBySourceId[wizardSourceId] ?? null) : null),
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        loadSourcesSuccess: () => {
            if (values.sources.length > 0) {
                actions.loadHealth()
            }
        },
        openWizardForSource: ({ sourceId }) => {
            actions.loadSetup(sourceId)
        },
        createSource: async () => {
            const projectId = values.currentTeamId
            const name = values.draftName.trim()
            if (projectId === null || name.length === 0 || values.draftRegion.length === 0) {
                actions.createSourceFinished()
                return
            }
            try {
                const created = await logsSourcesCreate(String(projectId), {
                    name,
                    provider: 'aws_cloudwatch',
                    enabled: true,
                    config: { region: values.draftRegion },
                })
                actions.sourceCreated(created)
                actions.loadSetup(created.id)
                actions.setWizardStep('connect')
                actions.loadSources()
            } catch (e: unknown) {
                toastApiError(e, 'Failed to create the source')
            } finally {
                actions.createSourceFinished()
            }
        },
        setWizardStep: ({ step }) => {
            if (step === 'waiting') {
                actions.loadHealth()
                cache.disposables.add(() => {
                    const id = window.setInterval(() => actions.loadHealth(), WAITING_POLL_MS)
                    return () => clearInterval(id)
                }, 'waitingPoll')
            } else {
                cache.disposables.dispose('waitingPoll')
            }
        },
        closeWizard: () => {
            cache.disposables.dispose('waitingPoll')
        },
        // The row flips as soon as the switch is clicked (see the `sources` reducer); a failed
        // request reloads the list to put it back.
        setSourceEnabled: async ({ sourceId, enabled }) => {
            const projectId = values.currentTeamId
            if (projectId === null) {
                actions.setSourceEnabledFinished()
                return
            }
            try {
                await logsSourcesPartialUpdate(String(projectId), sourceId, { enabled })
                actions.loadHealth()
            } catch (e: unknown) {
                toastApiError(e, 'Failed to update the source')
                actions.loadSources()
            } finally {
                actions.setSourceEnabledFinished()
            }
        },
        deleteSource: async ({ sourceId }) => {
            const projectId = values.currentTeamId
            if (projectId === null) {
                actions.deleteSourceFinished()
                return
            }
            try {
                await logsSourcesDestroy(String(projectId), sourceId)
                actions.sourceDeleted(sourceId)
                lemonToast.success('Source deleted')
            } catch (e: unknown) {
                toastApiError(e, 'Failed to delete the source')
            } finally {
                actions.deleteSourceFinished()
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadSources()
    }),
])
