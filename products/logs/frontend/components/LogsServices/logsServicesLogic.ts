export const logsServicesLogic = kea<logsServicesLogicType>([
    path(['products', 'logs', 'frontend', 'components', 'LogsServices', 'logsServicesLogic']),

    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),

    actions({
        setDateFrom: (dateFrom: string) => ({ dateFrom }),
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        setPage: (page: number) => ({ page }),
        setViewMode: (viewMode: ServicesViewMode) => ({ viewMode }),
        setSorting: (sorting: Sorting | null) => ({ sorting }),
        ensureSparklinesForPage: true,
        markSparklineRequested: (serviceNames: string[]) => ({ serviceNames }),
        unmarkSparklineRequested: (serviceNames: string[]) => ({ serviceNames }),
        mergeSparklinePoints: (points: _LogsServicesSparklineBucketApi[]) => ({ points }),
    }),

    reducers({
        dateFrom: [
            '-24h' as string,
            {
                setDateFrom: (_, { dateFrom }) => dateFrom,
            },
        ],
        searchTerm: [
            '' as string,
            {
                setSearchTerm: (_, { searchTerm }) => searchTerm,
            },
        ],
        viewMode: [
            'list' as ServicesViewMode,
            {
                setViewMode: (_, { viewMode }) => viewMode,
            },
        ],
        page: [
            1 as number,
            {
                setPage: (_, { page }) => Math.max(1, page),
            },
        ],
        sorting: [
            { columnKey: 'log_count', order: -1 } as Sorting | null,
            {
                setSorting: (_, { sorting }) => sorting,
            },
        ],
        // Sparkline buckets accumulate as pages are visited; a fresh aggregate
        // load resets them because the window or filters changed.
        sparklinePoints: [
            [] as _LogsServicesSparklineBucketApi[],
            {
                loadServicesDataSuccess: (_, { servicesData }) => servicesData.sparkline,
                mergeSparklinePoints: (state, { points }) => [...state, ...points],
            },
        ],
        // Tracks only in-flight page fetches; already-covered services are
        // recognized by their presence in sparklineByService.
        sparklineRequested: [
            {} as Record<string, boolean>,
            {
                loadServicesDataSuccess: () => ({}),
                markSparklineRequested: (state, { serviceNames }) => ({
                    ...state,
                    ...Object.fromEntries(serviceNames.map((name) => [name, true])),
                }),
                unmarkSparklineRequested: (state, { serviceNames }) => {
                    const next = { ...state }
                    for (const name of serviceNames) {
                        delete next[name]
                    }
                    return next
                },
            },
        ],
    }),

    loaders(({ values }) => ({
        servicesData: [
            EMPTY_SERVICES_RESPONSE,
            {
                loadServicesData: async () => {
                    if (!values.currentTeamId) {
                        return EMPTY_SERVICES_RESPONSE
                    }
                    return await logsServicesCreate(String(values.currentTeamId), {
                        query: {
                            dateRange: { date_from: values.dateFrom },
                            ...(values.searchTerm ? { serviceNameSearch: values.searchTerm } : {}),
                        },
                    })
                },
            },
        ],
    })),

    selectors({
        services: [(s) => [s.servicesData], (data: _LogsServicesResponseApi): ServiceRow[] => data.services],

        totalServices: [(s) => [s.servicesData], (data: _LogsServicesResponseApi): number => data.total_services],

        servicesSummary: [(s) => [s.servicesData], (data: _LogsServicesResponseApi) => data.summary],

        sortedServices: [
            (s) => [s.services, s.sorting],
            (services: ServiceRow[], sorting: Sorting | null): ServiceRow[] => {
                if (!sorting || !SORT_COMPARATORS[sorting.columnKey]) {
                    return services
                }
                const comparator = SORT_COMPARATORS[sorting.columnKey]
                return [...services].sort((a, b) => comparator(a, b) * sorting.order)
            },
        ],

        pageRows: [
            (s) => [s.sortedServices, s.page],
            (sortedServices: ServiceRow[], page: number): ServiceRow[] =>
                sortedServices.slice((page - 1) * SERVICES_PAGE_SIZE, page * SERVICES_PAGE_SIZE),
        ],

        sparklineByService: [
            (s) => [s.sparklinePoints],
            (points: _LogsServicesSparklineBucketApi[]): Record<string, { values: number[]; labels: string[] }> => {
                const byService: Record<string, Map<string, number>> = {}
                const allTimes = new Set<string>()

                for (const point of points) {
                    allTimes.add(point.time)
                    // The backend substitutes NO_SERVICE_LABEL for empty names
                    // before serializing, so point names match row names as-is.
                    const name = point.service_name
                    if (!byService[name]) {
                        byService[name] = new Map()
                    }
                    byService[name].set(point.time, point.count)
                }

                const sortedTimes = Array.from(allTimes).sort()
                const result: Record<string, { values: number[]; labels: string[] }> = {}

                for (const [serviceName, timeMap] of Object.entries(byService)) {
                    result[serviceName] = {
                        values: sortedTimes.map((t) => timeMap.get(t) ?? 0),
                        labels: sortedTimes,
                    }
                }

                return result
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        setDateFrom: () => {
            actions.setPage(1)
            actions.loadServicesData()
        },
        setSearchTerm: async (_, breakpoint) => {
            actions.setPage(1)
            await breakpoint(300)
            actions.loadServicesData()
        },
        setPage: () => {
            actions.ensureSparklinesForPage()
        },
        setSorting: () => {
            actions.setPage(1)
        },
        loadServicesDataSuccess: () => {
            actions.ensureSparklinesForPage()
        },
        ensureSparklinesForPage: async () => {
            const missing = values.pageRows
                .map((row) => row.service_name)
                .filter((name) => !values.sparklineByService[name] && !values.sparklineRequested[name])
            if (missing.length === 0 || !values.currentTeamId) {
                return
            }
            actions.markSparklineRequested(missing)
            const dateFrom = values.dateFrom
            const searchTerm = values.searchTerm
            let response
            try {
                response = await logsServicesCreate(String(values.currentTeamId), {
                    query: {
                        dateRange: { date_from: dateFrom },
                        serviceNames: missing.map((name) => (name === NO_SERVICE_LABEL ? '' : name)),
                    },
                })
            } catch {
                // Unmark so revisiting the page retries instead of showing
                // permanently empty sparklines.
                actions.unmarkSparklineRequested(missing)
                return
            }
            if (values.dateFrom !== dateFrom || values.searchTerm !== searchTerm) {
                return
            }
            actions.mergeSparklinePoints(response.sparkline)
        },
    })),

    afterMount(({ actions }) => {
        actions.loadServicesData()
    }),
])
