import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import type { Sorting } from 'lib/lemon-ui/LemonTable'
import { teamLogic } from 'scenes/teamLogic'

import { logsServicesCreate } from 'products/logs/frontend/generated/api'
import type {
    _LogsServiceAggregateApi,
    _LogsServicesResponseApi,
    _LogsServicesSparklineBucketApi,
    _LogsServicesSummaryApi,
} from 'products/logs/frontend/generated/api.schemas'

export type ServiceRow = _LogsServiceAggregateApi

/** How the v2 services surface draws the same list. Presentation only: it never changes which services are in the set. */
export type ServicesViewMode = 'list' | 'grid'

// Must stay at or below the backend's SPARKLINE_SERVICES_LIMIT: a page-turn
// sparkline request covers at most that many names, and names beyond it would
// come back without data.
export const SERVICES_PAGE_SIZE = 25

/** Placeholder the backend substitutes for an empty service name; map back to '' when filtering. */
export const NO_SERVICE_LABEL = '(no service)'

const EMPTY_SERVICES_RESPONSE: _LogsServicesResponseApi = {
    services: [],
    sparkline: [],
    total_services: 0,
}

const SORT_COMPARATORS: Record<string, (a: ServiceRow, b: ServiceRow) => number> = {
    service_name: (a, b) => a.service_name.localeCompare(b.service_name),
    log_count: (a, b) => a.log_count - b.log_count,
    error_rate: (a, b) => a.error_rate - b.error_rate,
}

