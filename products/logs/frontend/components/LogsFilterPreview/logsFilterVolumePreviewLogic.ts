import { MakeLogicType, actions, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'

import { FilterLogicalOperator, PropertyGroupFilter, UniversalFiltersGroup } from '~/types'

import { LogsFilterPreviewPoint } from './logsFilterVolumePreview'

const EMPTY_FILTER_GROUP: UniversalFiltersGroup = {
    type: FilterLogicalOperator.And,
    values: [],
}

/** Wrap inner group as the alerts / logs-viewer wire format expects. */
function wrapFilterGroup(inner: UniversalFiltersGroup): UniversalFiltersGroup {
    return { type: FilterLogicalOperator.And, values: [inner] as never }
}

function isFilterGroupNonEmpty(group: UniversalFiltersGroup): boolean {
    return Array.isArray(group.values) && group.values.length > 0
}

export interface LogsFilterVolumePreviewLogicProps {
    /** Isolates one mounted preview from another. Callers normally pass a `useId()`. */
    previewKey: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsFilterVolumePreviewLogicValues {
    filterGroup: UniversalFiltersGroup
    filterPreview: LogsFilterPreviewPoint[] | null
    filterPreviewLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsFilterVolumePreviewLogicActions {
    loadFilterPreview: (_: any) => any
    loadFilterPreviewFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFilterPreviewSuccess: (
        filterPreview: LogsFilterPreviewPoint[] | null,
        payload?: any
    ) => {
        filterPreview: LogsFilterPreviewPoint[] | null
        payload?: any
    }
    refreshFilterPreview: () => {
        value: true
    }
    setFilterGroup: (filterGroup: UniversalFiltersGroup) => {
        filterGroup: UniversalFiltersGroup
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsFilterVolumePreviewLogicMeta {
    key: string
}

export type logsFilterVolumePreviewLogicType = MakeLogicType<
    logsFilterVolumePreviewLogicValues,
    logsFilterVolumePreviewLogicActions,
    LogsFilterVolumePreviewLogicProps,
    logsFilterVolumePreviewLogicMeta
>

export const logsFilterVolumePreviewLogic = kea<logsFilterVolumePreviewLogicType>([
    path(['products', 'logs', 'frontend', 'components', 'LogsFilterPreview', 'logsFilterVolumePreviewLogic']),
    props({} as LogsFilterVolumePreviewLogicProps),
    key(({ previewKey }) => previewKey),

    actions({
        setFilterGroup: (filterGroup: UniversalFiltersGroup) => ({ filterGroup }),
        refreshFilterPreview: true,
    }),

    reducers({
        filterGroup: [
            EMPTY_FILTER_GROUP as UniversalFiltersGroup,
            {
                setFilterGroup: (_, { filterGroup }) => filterGroup,
            },
        ],
        // kea-loaders keeps the last successful value when a request fails. Consumers treat any
        // non-null value as describing the current filter, so a failed refresh would otherwise
        // chart the *previous* filter's volume and project storage from it. Dropping the value
        // routes the UI to its error-and-retry state instead.
        filterPreview: {
            loadFilterPreviewFailure: () => null,
        },
    }),

    loaders(({ values }) => ({
        filterPreview: [
            null as LogsFilterPreviewPoint[] | null,
            {
                loadFilterPreview: async (_, breakpoint) => {
                    await breakpoint(400)
                    if (!isFilterGroupNonEmpty(values.filterGroup)) {
                        return null
                    }
                    const response = await api.logs.sparkline({
                        query: {
                            dateRange: { date_from: '-24h', date_to: null },
                            filterGroup: wrapFilterGroup(values.filterGroup) as PropertyGroupFilter,
                            severityLevels: [],
                            serviceNames: [],
                            sparklineBreakdownBy: 'service',
                        },
                    })
                    // The backend returns each row keyed by the breakdown value ('service' here),
                    // not by the underlying column name (service_name).
                    return response as LogsFilterPreviewPoint[]
                },
            },
        ],
    })),

    listeners(({ actions }) => ({
        setFilterGroup: () => {
            actions.loadFilterPreview(null)
        },
        refreshFilterPreview: () => {
            actions.loadFilterPreview(null)
        },
    })),
])
