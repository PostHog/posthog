export const logsRetentionFormLogic = kea<logsRetentionFormLogicType>([
    path(['products', 'logs', 'frontend', 'components', 'LogsRetention', 'logsRetentionFormLogic']),
    props({} as LogsRetentionFormLogicProps),
    key(({ rule }) => rule?.id ?? 'new'),

    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    actions({
        applySuggestedName: true,
        refreshSuggestedName: true,
    }),

    loaders(({ props, values }) => ({
        suggestedName: [
            null as SuggestedName | null,
            {
                loadSuggestedName: async (_, breakpoint) => {
                    await breakpoint(SUGGEST_NAME_DEBOUNCE_MS)
                    // Only the create form suggests — an existing rule already has a name the user
                    // chose, so re-suggesting on every edit would just burn LLM calls.
                    if (props.rule) {
                        return null
                    }
                    const form = values.retentionForm
                    if (!isFilterGroupNonEmpty(form.filter_group)) {
                        return null
                    }
                    const payload = buildRetentionConfigPayload(form)
                    const fingerprint = JSON.stringify(payload)
                    // The filter editor re-emits identical groups (and the tier can be re-selected),
                    // so skip the request when nothing that feeds the prompt actually changed.
                    if (values.suggestedName?.fingerprint === fingerprint) {
                        return values.suggestedName
                    }
                    let response: { name?: string } | null
                    try {
                        response = await logsRetentionRulesSuggestNameCreate(
                            String(values.currentTeamId),
                            payload as never
                        )
                    } catch {
                        // A suggestion is cosmetic: missing AI consent (403), the shared AI throttle
                        // (429) and provider errors all just hide the hint. Swallowing here also keeps
                        // initKea's loader failure handler from toasting the 429 — it only suppresses
                        // 403 for load* actions. Scoped to the request so it can't swallow the
                        // breakpoint below, which aborts by throwing.
                        return null
                    }
                    // The filters may have moved on while the request was in flight — abort a
                    // superseded response rather than showing (and letting the user apply) a name for
                    // a configuration that no longer exists.
                    breakpoint()
                    const name = response?.name?.trim()
                    return name ? { fingerprint, name } : null
                },
            },
        ],
    })),

    listeners(({ actions, props, values }) => ({
        refreshSuggestedName: () => {
            actions.loadSuggestedName(null)
        },
        setRetentionFormValue: ({ name }) => {
            // retention_days feeds the prompt too ("...for 30 days"), so both fields re-suggest.
            if (!props.rule && (name === 'filter_group' || name === 'retention_days')) {
                actions.refreshSuggestedName()
            }
        },
        applySuggestedName: () => {
            const suggested = values.suggestedName?.name
            if (suggested) {
                actions.setRetentionFormValue('name', suggested)
            }
        },
    })),

    forms(({ props, values }) => ({
        retentionForm: {
            defaults: buildRetentionFormDefaults(props.rule),
            errors: (form: LogsRetentionFormType) => ({
                name: !form.name?.trim() ? 'Name is required' : undefined,
            }),
            submit: async (form: LogsRetentionFormType) => {
                const projectId = String(values.currentTeamId)
                try {
                    const payload = {
                        name: form.name.trim(),
                        enabled: form.enabled,
                        config: buildRetentionConfigPayload(form),
                    }
                    if (props.rule) {
                        const patch: PatchedLogsRetentionRuleApi = payload
                        await logsRetentionRulesPartialUpdate(projectId, props.rule.id, patch)
                        lemonToast.success('Retention rule updated')
                    } else {
                        await logsRetentionRulesCreate(projectId, payload as never)
                        lemonToast.success('Retention rule created')
                    }
                    router.actions.push(logsRetentionRulesSettingsUrl())
                } catch (e: any) {
                    lemonToast.error(e?.detail ?? e?.message ?? 'Failed to save rule')
                    throw e
                }
            },
        },
    })),
])
