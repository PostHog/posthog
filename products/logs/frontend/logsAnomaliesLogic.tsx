import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { teamLogic } from 'scenes/teamLogic'

import type { DateRange } from '~/queries/schema/schema-general'

import { serviceViewerUrl } from 'products/logs/frontend/components/LogsServices/serviceViewerUrl'
import { logsAnomaliesSeriesBandsCreate } from 'products/logs/frontend/generated/api'
import type { LogsSeriesBandSeriesApi, LogsSeriesBandsResponseApi } from 'products/logs/frontend/generated/api.schemas'

export const DEFAULT_VISIBLE_SERIES = 12

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAnomaliesLogicValues {
    currentTeamId: number | null // teamLogic
    hiddenSeriesCount: number
    seriesBands: LogsSeriesBandsResponseApi | null
    seriesBandsError: string | null
    seriesBandsLoading: boolean
    serviceName: string | null
    visibleSeries: LogsSeriesBandSeriesApi[]
    visibleSeriesCount: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAnomaliesLogicActions {
    loadSeriesBands: (_: any) => any
    loadSeriesBandsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSeriesBandsSuccess: (
        seriesBands: LogsSeriesBandsResponseApi | null,
        payload?: any
    ) => {
        seriesBands: LogsSeriesBandsResponseApi | null
        payload?: any
    }
    openLogsForBucket: (
        severity: string,
        dateRange: DateRange
    ) => {
        dateRange: DateRange
        severity: string
    }
    setServiceName: (serviceName: string | null) => {
        serviceName: string | null
    }
    showMoreSeries: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAnomaliesLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        visibleSeries: (
            seriesBands: LogsSeriesBandsResponseApi | null,
            visibleSeriesCount: number
        ) => LogsSeriesBandSeriesApi[]
        hiddenSeriesCount: (seriesBands: LogsSeriesBandsResponseApi | null, visibleSeriesCount: number) => number
    }
}

export type logsAnomaliesLogicType = MakeLogicType<
    logsAnomaliesLogicValues,
    logsAnomaliesLogicActions,
    Record<string, any>,
    logsAnomaliesLogicMeta
>

export const logsAnomaliesLogic = kea<logsAnomaliesLogicType>([
    path(['products', 'logs', 'frontend', 'logsAnomaliesLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        setServiceName: (serviceName: string | null) => ({ serviceName }),
        showMoreSeries: true,
        openLogsForBucket: (severity: string, dateRange: DateRange) => ({ severity, dateRange }),
    }),
    loaders(({ values }) => ({
        seriesBands: [
            null as LogsSeriesBandsResponseApi | null,
            {
                loadSeriesBands: async (_, breakpoint) => {
                    if (!values.serviceName || !values.currentTeamId) {
                        return null
                    }
                    const response = await logsAnomaliesSeriesBandsCreate(String(values.currentTeamId), {
                        serviceName: values.serviceName,
                    })
                    // A slow service can resolve after the user has moved to another one. Without
                    // this the late response would chart itself under the new service's name.
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers({
        serviceName: [
            null as string | null,
            {
                setServiceName: (_, { serviceName }) => serviceName,
            },
        ],
        // Charts from the previous service would misread as the new one, so a
        // service switch drops straight to the loading state.
        seriesBands: {
            setServiceName: () => null,
        },
        // The loader leaves the value null on failure, which reads the same as "still loading",
        // so the failure needs its own value for the tab to show a retry instead of a spinner.
        seriesBandsError: [
            null as string | null,
            {
                setServiceName: () => null,
                loadSeriesBands: () => null,
                loadSeriesBandsSuccess: () => null,
                loadSeriesBandsFailure: (_, { error }) => error || 'The request did not complete.',
            },
        ],
        visibleSeriesCount: [
            DEFAULT_VISIBLE_SERIES as number,
            {
                setServiceName: () => DEFAULT_VISIBLE_SERIES,
                showMoreSeries: (state) => state + DEFAULT_VISIBLE_SERIES,
            },
        ],
    }),
    selectors({
        visibleSeries: [
            (s) => [s.seriesBands, s.visibleSeriesCount],
            (seriesBands: LogsSeriesBandsResponseApi | null, visibleSeriesCount: number): LogsSeriesBandSeriesApi[] =>
                seriesBands ? seriesBands.series.slice(0, visibleSeriesCount) : [],
        ],
        hiddenSeriesCount: [
            (s) => [s.seriesBands, s.visibleSeriesCount],
            (seriesBands: LogsSeriesBandsResponseApi | null, visibleSeriesCount: number): number =>
                seriesBands ? Math.max(0, seriesBands.series.length - visibleSeriesCount) : 0,
        ],
    }),
    listeners(({ actions, values }) => ({
        setServiceName: ({ serviceName }) => {
            if (serviceName) {
                actions.loadSeriesBands({})
            }
        },
        openLogsForBucket: ({ severity, dateRange }) => {
            if (!values.serviceName) {
                return
            }
            router.actions.push(serviceViewerUrl(values.serviceName, { severityLevels: [severity], dateRange }))
        },
    })),
])
