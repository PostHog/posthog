import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import { dayjs } from 'lib/dayjs'
import type { LemonSelectOption } from 'lib/lemon-ui/LemonSelect'
import { teamLogic } from 'scenes/teamLogic'

import { logsAnomaliesScanCreate } from 'products/logs/frontend/generated/api'
import type { LogsAnomalyScanResponseApi } from 'products/logs/frontend/generated/api.schemas'

// The endpoint accepts at most 7 days per scan.
export const SCAN_WINDOW_OPTIONS: LemonSelectOption<number>[] = [
    { value: 1, label: 'Last hour' },
    { value: 6, label: 'Last 6 hours' },
    { value: 24, label: 'Last 24 hours' },
    { value: 72, label: 'Last 3 days' },
    { value: 168, label: 'Last 7 days' },
]

export const DEFAULT_SCAN_WINDOW_HOURS = 24

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAnomaliesLogicValues {
    currentTeamId: number | null // teamLogic
    scanDisabledReason: string | null
    scanResult: LogsAnomalyScanResponseApi | null
    scanResultLoading: boolean
    serviceName: string | null
    windowHours: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAnomaliesLogicActions {
    runScan: () => any
    runScanFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    runScanSuccess: (
        scanResult: LogsAnomalyScanResponseApi | null,
        payload?: any
    ) => {
        scanResult: LogsAnomalyScanResponseApi | null
        payload?: any
    }
    setServiceName: (serviceName: string | null) => {
        serviceName: string | null
    }
    setWindowHours: (windowHours: number) => {
        windowHours: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAnomaliesLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        scanDisabledReason: (serviceName: string | null, scanResultLoading: boolean) => string | null
    }
}

export type logsAnomaliesLogicType = MakeLogicType<
    logsAnomaliesLogicValues,
    logsAnomaliesLogicActions,
    Record<string, any>,
    logsAnomaliesLogicMeta
>

export const logsAnomaliesLogic = kea<logsAnomaliesLogicType>([
    path(['products', 'logs', 'frontend', 'logsAnomaliesLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        setServiceName: (serviceName: string | null) => ({ serviceName }),
        setWindowHours: (windowHours: number) => ({ windowHours }),
    }),
    loaders(({ values }) => ({
        scanResult: [
            null as LogsAnomalyScanResponseApi | null,
            {
                runScan: async () => {
                    if (!values.serviceName || !values.currentTeamId) {
                        return values.scanResult
                    }
                    const now = dayjs.utc()
                    return await logsAnomaliesScanCreate(String(values.currentTeamId), {
                        serviceName: values.serviceName,
                        dateRange: {
                            date_from: now.subtract(values.windowHours, 'hour').toISOString(),
                            date_to: now.toISOString(),
                        },
                    })
                },
            },
        ],
    })),
    reducers({
        serviceName: [
            null as string | null,
            {
                setServiceName: (_, { serviceName }) => serviceName,
            },
        ],
        windowHours: [
            DEFAULT_SCAN_WINDOW_HOURS as number,
            {
                setWindowHours: (_, { windowHours }) => windowHours,
            },
        ],
    }),
    selectors({
        scanDisabledReason: [
            (s) => [s.serviceName, s.scanResultLoading],
            (serviceName: string | null, scanResultLoading: boolean): string | null => {
                if (!serviceName) {
                    return 'Pick a service to scan first'
                }
                if (scanResultLoading) {
                    return 'A scan is already running'
                }
                return null
            },
        ],
    }),
    listeners(() => ({
        runScanFailure: ({ error }) => {
            // ApiError already extracts the endpoint's { error } body into the message.
            lemonToast.error(error || 'The anomaly scan failed. Try a shorter window.')
        },
    })),
])
