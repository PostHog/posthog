import { deepEqual as equal } from 'fast-equals'
import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router, urlToAction } from 'kea-router'

import { syncSearchParams, updateSearchParams } from '@posthog/products-error-tracking/frontend/utils'

import { trackedActionToUrl } from 'lib/logic/scenes/trackedActionToUrl'
import { Params } from 'scenes/sceneTypes'
import { teamLogic } from 'scenes/teamLogic'

import type { DateRange } from '~/queries/schema/schema-general'

import { serviceViewerUrl } from 'products/logs/frontend/components/LogsServices/serviceViewerUrl'
import { logsAnomaliesSeriesBandsCreate } from 'products/logs/frontend/generated/api'
import type { LogsSeriesBandSeriesApi, LogsSeriesBandsResponseApi } from 'products/logs/frontend/generated/api.schemas'

export const DEFAULT_VISIBLE_SERIES = 12
export const DEFAULT_ANOMALIES_DATE_RANGE: DateRange = { date_from: '-7d' }

// The viewer tab owns the `serviceNames` and `dateRange` params, so this tab cannot reuse those
// names: a bucket deep link or a viewer filter change writes them, and a shared name would let
// either tab rewrite the other one's selection.
const SERVICE_PARAM = 'anomaliesService'
const DATE_RANGE_PARAM = 'anomaliesDateRange'

// kea-router hands the param back as an object, but a hand-written link can carry the JSON string.
const parseDateRangeParam = (raw: unknown): DateRange | null => {
    if (typeof raw === 'string') {
        try {
            return JSON.parse(raw) as DateRange
        } catch {
            // Ignore malformed dateRange JSON in URL
            return null
        }
    }
    return raw && typeof raw === 'object' ? (raw as DateRange) : null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAnomaliesLogicValues {
    currentTeamId: number | null // teamLogic
    dateRange: DateRange
    hiddenSeriesCount: number
    seriesBands: LogsSeriesBandsResponseApi | null
    seriesBandsError: string | null
    seriesBandsLoading: boolean
    serviceName: string | null
    visibleSeries: LogsSeriesBandSeriesApi[]
    visibleSeriesCount: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAnomaliesLogicActions {
    loadSeriesBands: (_: any) => any
    loadSeriesBandsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSeriesBandsSuccess: (
        seriesBands: LogsSeriesBandsResponseApi | null,
        payload?: any
    ) => {
        seriesBands: LogsSeriesBandsResponseApi | null
        payload?: any
    }
    openLogsForBucket: (
        severity: string,
        dateRange: DateRange
    ) => {
        dateRange: DateRange
        severity: string
    }
    setDateRange: (dateRange: DateRange) => {
        dateRange: DateRange
    }
    setServiceName: (serviceName: string | null) => {
        serviceName: string | null
    }
    showMoreSeries: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface logsAnomaliesLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        visibleSeries: (
            seriesBands: LogsSeriesBandsResponseApi | null,
            visibleSeriesCount: number
        ) => LogsSeriesBandSeriesApi[]
        hiddenSeriesCount: (seriesBands: LogsSeriesBandsResponseApi | null, visibleSeriesCount: number) => number
    }
}

export type logsAnomaliesLogicType = MakeLogicType<
    logsAnomaliesLogicValues,
    logsAnomaliesLogicActions,
    Record<string, any>,
    logsAnomaliesLogicMeta
>

export const logsAnomaliesLogic = kea<logsAnomaliesLogicType>([
    path(['products', 'logs', 'frontend', 'logsAnomaliesLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        setServiceName: (serviceName: string | null) => ({ serviceName }),
        setDateRange: (dateRange: DateRange) => ({ dateRange }),
        showMoreSeries: true,
        openLogsForBucket: (severity: string, dateRange: DateRange) => ({ severity, dateRange }),
    }),

    urlToAction(({ actions, values }) => {
        // The tab mounts this logic afresh on each visit, so the URL is the only place the
        // selection survives a tab switch, a reload, or a link sent to someone else.
        const syncFromUrl = (_: any, params: Params): void => {
            // The window goes first: on a link that names both, the reload the service triggers
            // then already carries that link's window.
            const dateRange = parseDateRangeParam(params[DATE_RANGE_PARAM]) ?? DEFAULT_ANOMALIES_DATE_RANGE
            if (!equal(dateRange, values.dateRange)) {
                actions.setDateRange(dateRange)
            }
            const serviceParam = params[SERVICE_PARAM]
            const serviceName = typeof serviceParam === 'string' && serviceParam ? serviceParam : null
            // Comparing before dispatching is what keeps this off a loop with the writer below,
            // and it stops a URL change from another tab reloading these charts.
            if (serviceName !== values.serviceName) {
                actions.setServiceName(serviceName)
            }
        }
        return {
            '*': syncFromUrl,
        }
    }),

    trackedActionToUrl(({ values }) => {
        const syncUrl = (): ReturnType<typeof syncSearchParams> =>
            syncSearchParams(router, (params: Params) => {
                updateSearchParams(params, SERVICE_PARAM, values.serviceName, null)
                updateSearchParams(params, DATE_RANGE_PARAM, values.dateRange, DEFAULT_ANOMALIES_DATE_RANGE)
                return params
            })

        return {
            setServiceName: () => syncUrl(),
            setDateRange: () => syncUrl(),
        }
    }),
    loaders(({ values }) => ({
        seriesBands: [
            null as LogsSeriesBandsResponseApi | null,
            {
                loadSeriesBands: async (_, breakpoint) => {
                    if (!values.serviceName || !values.currentTeamId) {
                        return null
                    }
                    const response = await logsAnomaliesSeriesBandsCreate(String(values.currentTeamId), {
                        serviceName: values.serviceName,
                        dateRange: values.dateRange,
                    })
                    // A slow service can resolve after the user has moved to another one. Without
                    // this the late response would chart itself under the new service's name.
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers({
        serviceName: [
            null as string | null,
            {
                setServiceName: (_, { serviceName }) => serviceName,
            },
        ],
        dateRange: [
            DEFAULT_ANOMALIES_DATE_RANGE as DateRange,
            {
                setDateRange: (_, { dateRange }) => dateRange,
            },
        ],
        // Charts from the previous service would misread as the new one, so a
        // service switch drops straight to the loading state.
        seriesBands: {
            setServiceName: () => null,
        },
        // The loader leaves the value null on failure, which reads the same as "still loading",
        // so the failure needs its own value for the tab to show a retry instead of a spinner.
        seriesBandsError: [
            null as string | null,
            {
                setServiceName: () => null,
                loadSeriesBands: () => null,
                loadSeriesBandsSuccess: () => null,
                // A rejected window is the user's to fix, so the backend's sentence has to reach
                // the banner ahead of the generic "Non-OK response" message.
                loadSeriesBandsFailure: (_, { error, errorObject }) =>
                    errorObject?.data?.error || errorObject?.detail || error || 'The request did not complete.',
            },
        ],
        visibleSeriesCount: [
            DEFAULT_VISIBLE_SERIES as number,
            {
                setServiceName: () => DEFAULT_VISIBLE_SERIES,
                showMoreSeries: (state) => state + DEFAULT_VISIBLE_SERIES,
            },
        ],
    }),
    selectors({
        visibleSeries: [
            (s) => [s.seriesBands, s.visibleSeriesCount],
            (seriesBands: LogsSeriesBandsResponseApi | null, visibleSeriesCount: number): LogsSeriesBandSeriesApi[] =>
                seriesBands ? seriesBands.series.slice(0, visibleSeriesCount) : [],
        ],
        hiddenSeriesCount: [
            (s) => [s.seriesBands, s.visibleSeriesCount],
            (seriesBands: LogsSeriesBandsResponseApi | null, visibleSeriesCount: number): number =>
                seriesBands ? Math.max(0, seriesBands.series.length - visibleSeriesCount) : 0,
        ],
    }),
    listeners(({ actions, values }) => ({
        setServiceName: ({ serviceName }) => {
            if (serviceName) {
                actions.loadSeriesBands({})
            }
        },
        setDateRange: () => {
            if (values.serviceName) {
                actions.loadSeriesBands({})
            }
        },
        openLogsForBucket: ({ severity, dateRange }) => {
            if (!values.serviceName) {
                return
            }
            router.actions.push(serviceViewerUrl(values.serviceName, { severityLevels: [severity], dateRange }))
        },
    })),
])
