import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
} from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import posthog from 'lib/posthog-typed'
import { projectLogic } from 'scenes/projectLogic'

import type { FeatureFlagApi } from 'products/feature_flags/frontend/generated/api.schemas'
import * as todayApi from 'products/today/frontend/generated/api'
import type { WorkRunApiParams, WorkThreadApi } from 'products/today/frontend/generated/api.schemas'

import type { LinkedBroadcastDTOApi, PatchedUpdateReleaseApi, ReleaseDTOApi } from './generated/api.schemas'
import { releaseLogic } from './releaseLogic'

// pinned: the work source name and action ids the release server code emits.
const RELEASE_WORK_SOURCE = 'release'
const SCHEDULE_ROLLOUT_ACTION = 'schedule_rollout'

export interface ReleaseWorkThreadLogicProps {
    releaseId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface releaseWorkThreadLogicValues {
    currentProjectId: number | null // projectLogic
    thread: WorkThreadApi | null
    threadLoading: boolean
    threadFailed: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface releaseWorkThreadLogicActions {
    loadFlagsSuccess: (flags: FeatureFlagApi[]) => { flags: FeatureFlagApi[] } // releaseLogic
    openSchedule: (flagId: number) => { flagId: number } // releaseLogic
    setReleaseLocally: (update: {
        id: string
        changes: PatchedUpdateReleaseApi
        broadcasts?: LinkedBroadcastDTOApi[]
        linked?: Pick<ReleaseDTOApi, 'surveys' | 'insights'>
    }) => {
        id: string
        changes: PatchedUpdateReleaseApi
        broadcasts?: LinkedBroadcastDTOApi[]
        linked?: Pick<ReleaseDTOApi, 'surveys' | 'insights'>
    } // releaseLogic
    loadReleaseWorkThread: () => void
    loadReleaseWorkThreadSuccess: (thread: WorkThreadApi | null) => { thread: WorkThreadApi | null }
    loadReleaseWorkThreadFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    runAction: (actionId: string, params: WorkRunApiParams) => { actionId: string; params: WorkRunApiParams }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface releaseWorkThreadLogicMeta {
    key: string
}

export type releaseWorkThreadLogicType = MakeLogicType<
    releaseWorkThreadLogicValues,
    releaseWorkThreadLogicActions,
    ReleaseWorkThreadLogicProps,
    releaseWorkThreadLogicMeta
>

export const releaseWorkThreadLogic: LogicWrapper<releaseWorkThreadLogicType> = kea<releaseWorkThreadLogicType>([
    props({} as ReleaseWorkThreadLogicProps),
    key((props) => props.releaseId),
    path((key) => ['products', 'release', 'frontend', 'releaseWorkThreadLogic', key]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
        actions: [releaseLogic, ['loadFlagsSuccess', 'openSchedule', 'setReleaseLocally']],
    })),
    actions({
        runAction: (actionId: string, params: WorkRunApiParams) => ({ actionId, params }),
    }),
    loaders(({ props, values }) => ({
        thread: [
            null as WorkThreadApi | null,
            {
                loadReleaseWorkThread: async (_, breakpoint) => {
                    const response = await todayApi.todayWorkThreadsRetrieve(String(values.currentProjectId), {
                        source: RELEASE_WORK_SOURCE,
                        ref: props.releaseId,
                    })
                    breakpoint()
                    return response.results[0] ?? null
                },
            },
        ],
    })),
    reducers({
        threadFailed: [
            false,
            {
                loadReleaseWorkThread: () => false,
                loadReleaseWorkThreadSuccess: () => false,
                loadReleaseWorkThreadFailure: () => true,
            },
        ],
    }),
    listeners(({ actions, props }) => ({
        // releaseLogic loads the flags again after the releases load, after a link changes and after the schedule
        // dialog closes. Those are the changes that move the release's steps.
        loadFlagsSuccess: () => {
            actions.loadReleaseWorkThread()
        },
        setReleaseLocally: ({ id, linked }) => {
            // Only the update that carries what the server saved has `linked`. The optimistic one runs before the save.
            if (id === props.releaseId && linked !== undefined) {
                actions.loadReleaseWorkThread()
            }
        },
        runAction: ({ actionId, params }) => {
            const flagId = params?.flag_id
            if (actionId === SCHEDULE_ROLLOUT_ACTION && typeof flagId === 'number') {
                actions.openSchedule(flagId)
                return
            }
            posthog.captureException(new Error('Release work thread action is not handled'), {
                action_id: actionId,
            })
            lemonToast.error('This step could not start here. Refresh the page and try again.')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadReleaseWorkThread()
    }),
])
