export const ALL_PAGE_SIZE = 50
const SEARCH_DEBOUNCE_MS = 250

export type ReleaseAllType = 'release' | 'feature_flag' | 'experiment' | 'early_access_feature'
export type ReleaseAllFilter = 'all' | ReleaseAllType

export interface ReleaseAllRow {
    key: string
    type: ReleaseAllType
    name: string
    status: string
    createdAt: string
    href: string
}

interface SourcePage {
    rows: ReleaseAllRow[]
    hasMore: boolean
}

interface SourceState {
    rows: ReleaseAllRow[]
    offset: number
    hasMore: boolean
    loading: boolean
    failed: boolean
}

const PAGED_TYPES: ReleaseAllType[] = ['feature_flag', 'experiment', 'early_access_feature']
const EMPTY_SOURCE: SourceState = { rows: [], offset: 0, hasMore: true, loading: false, failed: false }

function emptySources(): Record<string, SourceState> {
    return Object.fromEntries(PAGED_TYPES.map((type) => [type, EMPTY_SOURCE]))
}

function capitalize(text: string): string {
    return text.charAt(0).toUpperCase() + text.slice(1).replace(/-/g, ' ')
}

async function fetchPage(type: ReleaseAllType, projectId: string, search: string, offset: number): Promise<SourcePage> {
    const query = search || undefined
    if (type === 'feature_flag') {
        const page = await releasesCatalogFlagsRetrieve(projectId, { search: query, limit: ALL_PAGE_SIZE, offset })
        return {
            hasMore: page.has_more,
            rows: page.results.map((flag) => ({
                key: `flag-${flag.id}`,
                type,
                name: flag.key,
                status: flag.active ? 'Active' : 'Disabled',
                createdAt: flag.created_at,
                href: urls.featureFlag(flag.id),
            })),
        }
    }
    if (type === 'experiment') {
        const page = await experimentsList(projectId, {
            search: query,
            order: '-created_at',
            limit: ALL_PAGE_SIZE,
            offset,
        })
        return {
            hasMore: !!page.next,
            rows: page.results.map((experiment) => ({
                key: `experiment-${experiment.id}`,
                type,
                name: experiment.name,
                status: experiment.end_date ? 'Complete' : experiment.start_date ? 'Running' : 'Draft',
                createdAt: experiment.created_at ?? '',
                href: urls.experiment(experiment.id as number),
            })),
        }
    }
    const page = await earlyAccessFeatureList(projectId, { limit: ALL_PAGE_SIZE, offset })
    const needle = search.toLowerCase()
    return {
        hasMore: !!page.next,
        rows: page.results
            .filter((item) => !needle || item.name.toLowerCase().includes(needle))
            .map((item) => ({
                key: `ea-${item.id}`,
                type,
                name: item.name,
                status: capitalize(item.stage),
                createdAt: item.created_at ?? '',
                href: urls.earlyAccessFeature(item.id),
            })),
    }
}

function releaseRows(rows: ReleaseRow[], search: string): ReleaseAllRow[] {
    const needle = search.toLowerCase()
    return rows
        .filter((row) => !needle || row.name.toLowerCase().includes(needle))
        .map((row) => ({
            key: `release-${row.id}`,
            type: 'release',
            name: row.name,
            status: STAGE_LABEL[row.stage],
            createdAt: row.createdAt,
            href: urls.release(row.id),
        }))
}

const newestFirst = (a: ReleaseAllRow, b: ReleaseAllRow): number => b.createdAt.localeCompare(a.createdAt)

