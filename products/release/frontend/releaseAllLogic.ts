export type releaseAllLogicType = MakeLogicType<releaseAllLogicValues, releaseAllLogicActions, Record<string, any>, releaseAllLogicMeta>;

export const releaseAllLogic = kea<releaseAllLogicType>([
    path(['products', 'release', 'frontend', 'releaseAllLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId'], releaseLogic, ['rows', 'releasesReady']] })),
    actions({
        setFilter: (filter: ReleaseAllFilter) => ({ filter }),
        setSearch: (search: string) => ({ search }),
        setAppliedSearch: (search: string) => ({ search }),
        loadMore: true,
        keepRows: (rows: ReleaseAllRow[]) => ({ rows }),
        loadSource: (type: ReleaseAllType) => ({ type }),
        sourceLoaded: (type: ReleaseAllType, search: string, page: SourcePage) => ({ type, search, page }),
        sourceFailed: (type: ReleaseAllType, search: string) => ({ type, search }),
    }),
    reducers({
        filter: ['all' as ReleaseAllFilter, { setFilter: (_, { filter }) => filter }],
        search: ['', { setSearch: (_, { search }) => search }],
        appliedSearch: ['', { setAppliedSearch: (_, { search }) => search }],
        keptRows: [[] as ReleaseAllRow[], { keepRows: (_, { rows }) => rows }],
        sources: [
            emptySources(),
            {
                setAppliedSearch: () => emptySources(),
                loadSource: (state, { type }) => ({
                    ...state,
                    [type]: { ...state[type], loading: true, failed: false },
                }),
                sourceLoaded: (state, { type, page }) => ({
                    ...state,
                    [type]: {
                        rows: [...state[type].rows, ...page.rows],
                        offset: state[type].offset + ALL_PAGE_SIZE,
                        hasMore: page.hasMore,
                        loading: false,
                        failed: false,
                    },
                }),
                sourceFailed: (state, { type }) => ({
                    ...state,
                    [type]: { ...state[type], hasMore: false, loading: false, failed: true },
                }),
            },
        ],
    }),
    selectors({
        activeTypes: [
            (s) => [s.filter],
            (filter: ReleaseAllFilter): ReleaseAllType[] => (filter === 'all' ? ['release', ...PAGED_TYPES] : [filter]),
        ],
        cutoff: [
            (s) => [s.sources, s.activeTypes],
            (sources: Record<string, SourceState>, activeTypes: ReleaseAllType[]): string | null => {
                const open = activeTypes
                    .filter((type) => type !== 'release' && sources[type].hasMore && sources[type].rows.length)
                    .map((type) => sources[type].rows[sources[type].rows.length - 1].createdAt)
                return open.length ? open.reduce((latest, value) => (value > latest ? value : latest)) : null
            },
        ],
        visibleRows: [
            (s) => [s.sources, s.activeTypes, s.rows, s.appliedSearch, s.cutoff],
            (
                sources: Record<string, SourceState>,
                activeTypes: ReleaseAllType[],
                rows: ReleaseRow[],
                appliedSearch: string,
                cutoff: string | null
            ): ReleaseAllRow[] => {
                const merged = activeTypes
                    .flatMap((type) => (type === 'release' ? releaseRows(rows, appliedSearch) : sources[type].rows))
                    .sort(newestFirst)
                return cutoff ? merged.filter((row) => row.createdAt >= cutoff) : merged
            },
        ],
        hasMore: [
            (s) => [s.sources, s.activeTypes],
            (sources: Record<string, SourceState>, activeTypes: ReleaseAllType[]): boolean =>
                activeTypes.some((type) => type !== 'release' && sources[type].hasMore),
        ],
        loading: [
            (s) => [s.sources, s.activeTypes, s.releasesReady],
            (sources: Record<string, SourceState>, activeTypes: ReleaseAllType[], releasesReady: boolean): boolean =>
                activeTypes.some((type) => (type === 'release' ? !releasesReady : sources[type].loading)),
        ],
        firstLoad: [
            (s) => [s.sources, s.activeTypes, s.releasesReady],
            (sources: Record<string, SourceState>, activeTypes: ReleaseAllType[], releasesReady: boolean): boolean =>
                activeTypes.some((type) =>
                    type === 'release' ? !releasesReady : sources[type].offset === 0 && !sources[type].failed
                ),
        ],
        displayRows: [
            (s) => [s.firstLoad, s.keptRows, s.visibleRows],
            (firstLoad: boolean, keptRows: ReleaseAllRow[], visibleRows: ReleaseAllRow[]): ReleaseAllRow[] =>
                firstLoad && !visibleRows.length ? keptRows : visibleRows,
        ],
        showSkeleton: [
            (s) => [s.firstLoad, s.displayRows],
            (firstLoad: boolean, displayRows: ReleaseAllRow[]): boolean => firstLoad && !displayRows.length,
        ],
        failedTypes: [
            (s) => [s.sources, s.activeTypes],
            (sources: Record<string, SourceState>, activeTypes: ReleaseAllType[]): ReleaseAllType[] =>
                activeTypes.filter((type) => type !== 'release' && sources[type].failed),
        ],
    }),
    listeners(({ actions, values }) => ({
        setSearch: async ({ search }, breakpoint) => {
            await breakpoint(SEARCH_DEBOUNCE_MS)
            if (search.trim() !== values.appliedSearch) {
                actions.keepRows(values.displayRows)
                actions.setAppliedSearch(search.trim())
            }
        },
        setAppliedSearch: ({ search }) => {
            if (search) {
                posthog.capture('release view all searched', { filter: values.filter })
            }
            actions.loadMore()
        },
        setFilter: ({ filter }) => {
            actions.keepRows(values.displayRows.filter((row) => filter === 'all' || row.type === filter))
            posthog.capture('release view all filtered', { filter })
            actions.loadMore()
        },
        loadMore: () => {
            for (const type of values.activeTypes) {
                if (type === 'release') {
                    continue
                }
                const source = values.sources[type]
                const behind =
                    !source.rows.length ||
                    values.cutoff === null ||
                    source.rows[source.rows.length - 1].createdAt <= values.cutoff
                if (source.hasMore && !source.loading && behind) {
                    actions.loadSource(type)
                }
            }
        },
        loadSource: async ({ type }) => {
            const search = values.appliedSearch
            try {
                const page = await fetchPage(type, String(values.currentProjectId), search, values.sources[type].offset)
                if (search === values.appliedSearch) {
                    actions.sourceLoaded(type, search, page)
                }
            } catch {
                if (search === values.appliedSearch) {
                    actions.sourceFailed(type, search)
                }
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadMore()
    }),
])
