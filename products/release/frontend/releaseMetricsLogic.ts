import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'

import {
    METRIC_SUMMARY_DEFAULT,
    type MetricSummary,
    computeMetricSummary,
    selectCurrentSeries,
} from 'lib/components/Metric/metricSummary'
import { retryImport } from 'lib/utils/retryImport'
import { projectLogic } from 'scenes/projectLogic'

import { ChartDisplayType } from '~/types'

import { insightsRetrieve } from 'products/product_analytics/frontend/generated/api'
import type { QueryStatusApi } from 'products/product_analytics/frontend/generated/api.schemas'

export type ReleaseMetric =
    | { status: 'loading' }
    | { status: 'failed' }
    | {
          status: 'ready'
          name: string
          shortId: string
          value: number | null
          values: number[]
          labels: string[]
      }

interface TrendSeries {
    data?: unknown
    labels?: unknown
    days?: unknown
    count?: unknown
    aggregated_value?: unknown
    compare_label?: string | null
}

interface MetricQuery {
    source?: { trendsFilter?: { display?: string; metricSummary?: MetricSummary } }
}

function isNumberList(value: unknown): value is number[] {
    return Array.isArray(value) && value.every((item) => typeof item === 'number')
}

function finite(value: unknown): number | null {
    return typeof value === 'number' && Number.isFinite(value) ? value : null
}

function seriesLabels(series: TrendSeries, length: number): string[] {
    const days = Array.isArray(series.days) ? series.days.map(String) : []
    if (days.length === length) {
        return days
    }
    return Array.isArray(series.labels) ? series.labels.map(String) : []
}

function seriesValue(series: TrendSeries, values: number[], query: unknown): number | null {
    const aggregated = finite(series.aggregated_value)
    const trendsFilter = (query as MetricQuery | null | undefined)?.source?.trendsFilter
    if (trendsFilter?.display !== ChartDisplayType.Metric) {
        return aggregated ?? values.at(-1) ?? null
    }
    const total = aggregated ?? finite(series.count)
    return total === null
        ? null
        : computeMetricSummary(trendsFilter.metricSummary ?? METRIC_SUMMARY_DEFAULT, total, values)
}

export function metricFromResult(
    result: unknown,
    query?: unknown
): Pick<Extract<ReleaseMetric, { status: 'ready' }>, 'value' | 'values' | 'labels'> {
    const series = Array.isArray(result) ? selectCurrentSeries(result as TrendSeries[]) : undefined
    if (!series) {
        return { value: null, values: [], labels: [] }
    }
    const values = isNumberList(series.data) ? series.data : []
    return { value: seriesValue(series, values, query), values, labels: seriesLabels(series, values.length) }
}

async function loadMetric(projectId: string, insightId: number, signal: AbortSignal): Promise<ReleaseMetric> {
    let insight = await insightsRetrieve(projectId, insightId, { refresh: 'async' }, { signal })
    const pending = insight.query_status as QueryStatusApi | null | undefined
    if (pending?.id && !pending.complete && !pending.error) {
        const { pollForResults, isExpiredQueryStatusError } = await retryImport(() => import('~/queries/query'))
        try {
            if ((await pollForResults(pending.id, { signal })).error) {
                return { status: 'failed' }
            }
        } catch (error) {
            if (!isExpiredQueryStatusError(error)) {
                throw error
            }
        }
        insight = await insightsRetrieve(projectId, insightId, { refresh: 'force_cache' }, { signal })
    }
    if ((insight.query_status as QueryStatusApi | null | undefined)?.error) {
        return { status: 'failed' }
    }
    return {
        status: 'ready',
        name: insight.name || insight.derived_name || 'Untitled insight',
        shortId: insight.short_id,
        ...metricFromResult(insight.result, insight.query),
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface releaseMetricsLogicValues {
    currentProjectId: number | null // projectLogic
    metrics: Record<number, ReleaseMetric>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface releaseMetricsLogicActions {
    loadMetrics: (insightIds: number[]) => {
        insightIds: number[]
    }
    metricLoaded: (
        insightId: number,
        metric: ReleaseMetric
    ) => {
        insightId: number
        metric: ReleaseMetric
    }
}

export type releaseMetricsLogicType = MakeLogicType<releaseMetricsLogicValues, releaseMetricsLogicActions>

export const releaseMetricsLogic = kea<releaseMetricsLogicType>([
    path(['products', 'release', 'frontend', 'releaseMetricsLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        loadMetrics: (insightIds: number[]) => ({ insightIds }),
        metricLoaded: (insightId: number, metric: ReleaseMetric) => ({ insightId, metric }),
    }),
    reducers({
        metrics: [
            {} as Record<number, ReleaseMetric>,
            {
                loadMetrics: (state, { insightIds }) => ({
                    ...state,
                    ...Object.fromEntries(
                        insightIds
                            .filter((insightId) => !state[insightId] || state[insightId].status === 'failed')
                            .map((insightId) => [insightId, { status: 'loading' } as ReleaseMetric])
                    ),
                }),
                metricLoaded: (state, { insightId, metric }) => ({ ...state, [insightId]: metric }),
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadMetrics: async ({ insightIds }) => {
            cache.inFlight = cache.inFlight ?? new Set<number>()
            const todo = insightIds.filter(
                (insightId) => values.metrics[insightId]?.status === 'loading' && !cache.inFlight.has(insightId)
            )
            const signal: AbortSignal = cache.controller.signal
            todo.forEach((insightId) => cache.inFlight.add(insightId))
            await Promise.all(
                todo.map(async (insightId) => {
                    try {
                        const metric = await loadMetric(String(values.currentProjectId), insightId, signal)
                        if (!signal.aborted) {
                            actions.metricLoaded(insightId, metric)
                        }
                    } catch {
                        if (!signal.aborted) {
                            actions.metricLoaded(insightId, { status: 'failed' })
                        }
                    } finally {
                        cache.inFlight.delete(insightId)
                    }
                })
            )
        },
    })),
    afterMount(({ cache }) => {
        cache.disposables.add(
            () => {
                cache.controller = new AbortController()
                return () => cache.controller.abort()
            },
            'abortLoads',
            { pauseOnPageHidden: false }
        )
    }),
])
