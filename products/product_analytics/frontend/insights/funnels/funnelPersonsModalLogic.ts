import { MakeLogicType, actions, connect, kea, key, listeners, path, props, selectors } from 'kea'

import { insightLogic } from 'scenes/insights/insightLogic'
import { keyForInsightLogicProps } from 'scenes/insights/sharedUtils'
import { funnelTitle } from 'scenes/trends/persons-modal/persons-modal-utils'
import { openPersonsModal } from 'scenes/trends/persons-modal/PersonsModal'

import { FunnelsActorsQuery, NodeKind } from '~/queries/schema/schema-general'
import type { FunnelsFilter, FunnelsQuery } from '~/queries/schema/schema-general'
import { FunnelStep, FunnelStepWithConversionMetrics, InsightLogicProps } from '~/types'
import type { FunnelStepWithNestedBreakdown } from '~/types'

import { funnelDataLogic } from './funnelDataLogic'

const DEFAULT_FUNNEL_LOGIC_KEY = 'default_funnel_key'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface funnelPersonsModalLogicValues {
    funnelsFilter: FunnelsFilter | null | undefined // funnelDataLogic
    querySource: FunnelsQuery | null // funnelDataLogic
    steps: FunnelStepWithNestedBreakdown[] // funnelDataLogic
    isInDashboardContext: boolean // insightLogic
    isInExperimentContext: boolean // insightLogic
    canOpenPersonModal: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface funnelPersonsModalLogicActions {
    openPersonsModalForSeries: ({
        step,
        series,
        converted,
    }: {
        converted: boolean
        series: Omit<FunnelStepWithConversionMetrics, 'nested_breakdown'>
        step: FunnelStep
    }) => {
        converted: boolean
        series: Omit<FunnelStepWithConversionMetrics, 'nested_breakdown'>
        step: FunnelStep
    }
    openPersonsModalForStep: ({
        step,
        stepIndex,
        converted,
    }: {
        converted: boolean
        step: FunnelStep
        stepIndex?: number
    }) => {
        converted: boolean
        step: FunnelStep
        stepIndex: number | undefined
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface funnelPersonsModalLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        canOpenPersonModal: (funnelsFilter: FunnelsFilter | null | undefined) => boolean
    }
}

export type funnelPersonsModalLogicType = MakeLogicType<
    funnelPersonsModalLogicValues,
    funnelPersonsModalLogicActions,
    InsightLogicProps,
    funnelPersonsModalLogicMeta
>

export const funnelPersonsModalLogic = kea<funnelPersonsModalLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps(DEFAULT_FUNNEL_LOGIC_KEY)),
    path((key) => ['scenes', 'funnels', 'funnelPersonsModalLogic', key]),

    connect((props: InsightLogicProps) => ({
        values: [
            insightLogic(props),
            ['isInDashboardContext', 'isInExperimentContext'],
            funnelDataLogic(props),
            ['steps', 'querySource', 'funnelsFilter'],
        ],
    })),

    actions({
        openPersonsModalForStep: ({
            step,
            stepIndex,
            converted,
        }: {
            step: FunnelStep
            stepIndex?: number
            converted: boolean
        }) => ({
            step,
            stepIndex,
            converted,
        }),
        openPersonsModalForSeries: ({
            step,
            series,
            converted,
        }: {
            step: FunnelStep
            series: Omit<FunnelStepWithConversionMetrics, 'nested_breakdown'>
            converted: boolean
        }) => ({
            step,
            series,
            converted,
        }),
    }),

    selectors({
        canOpenPersonModal: [
            (s) => [s.funnelsFilter],
            (funnelsFilter: null | import('~/queries/schema/schema-general').FunnelsFilter | undefined): boolean => {
                if (funnelsFilter?.customAggregationTarget) {
                    return false
                }

                const aggregateByHogQL = funnelsFilter?.funnelAggregateByHogQL

                // Allow opening modal persons/groups
                if (!aggregateByHogQL) {
                    return true
                }

                // Allow opening modal when aggregating by unique sessions (properties.$session_id)
                if (aggregateByHogQL === 'properties.$session_id') {
                    return true
                }

                return false
            },
        ],
    }),

    listeners(({ values }) => ({
        openPersonsModalForStep: ({ step, stepIndex, converted }) => {
            // Note - when in a legend the step.order is always 0 so we use stepIndex instead
            const stepNo = typeof stepIndex === 'number' ? stepIndex + 1 : step.order + 1
            // A first-step drop-off (funnelStep -1) is invalid — the backend rejects it with a 500. No UI
            // exposes one (the footer/legend hide the drop-off control on step 1, and compare's first-step
            // volume gap is non-interactive), but guard the listener so any invalid call opens nothing.
            if (!converted && stepNo === 1) {
                return
            }
            const title = funnelTitle({
                converted,
                step: stepNo,
                label: step.name,
                seriesId: step.order,
                order_type: values.funnelsFilter?.funnelOrderType,
            })

            // openPersonsModalForStep is for the baseline - for breakdown series use openPersonsModalForSeries
            const query: FunnelsActorsQuery = {
                kind: NodeKind.FunnelsActorsQuery,
                source: values.querySource!,
                funnelStep: converted ? stepNo : -stepNo,
                includeRecordings: true,
            }
            openPersonsModal({ title, query, additionalSelect: { matched_recordings: 'matched_recordings' } })
        },
        openPersonsModalForSeries: ({ step, series, converted }) => {
            const stepNo = step.order + 1
            // See openPersonsModalForStep: a first-step drop-off (funnelStep -1) is invalid.
            if (!converted && stepNo === 1) {
                return
            }
            // No breakdown value in the title: the modal's breakdown dropdown communicates (and can
            // change) the selected value, so a static title would go stale.
            const title = funnelTitle({
                converted,
                step: stepNo,
                label: step.name,
                seriesId: step.order,
                order_type: values.funnelsFilter?.funnelOrderType,
            })

            // Version of openPersonsModalForStep that accurately handles breakdown series
            const query: FunnelsActorsQuery = {
                kind: NodeKind.FunnelsActorsQuery,
                source: values.querySource!,
                funnelStep: converted ? stepNo : -stepNo,
                funnelStepBreakdown: series.breakdown_value === 'Baseline' ? null : series.breakdown_value,
                // In compare mode each bar belongs to one period; scope its actors to that period.
                compare: series.compare_label,
                includeRecordings: true,
            }
            openPersonsModal({ title, query, additionalSelect: { matched_recordings: 'matched_recordings' } })
        },
    })),
])
