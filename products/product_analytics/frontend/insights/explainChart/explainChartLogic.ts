export const explainChartLogic: LogicWrapper<explainChartLogicType> = kea<explainChartLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'explainChart', 'explainChartLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            maxGlobalLogic,
            ['effectivePhaiView'],
            aiConsentLogic,
            ['dataProcessingAccepted'],
            insightLogic(props),
            ['insight', 'savedInsight'],
            insightDataLogic(props),
            ['query'],
            teamLogic,
            ['baseCurrency'],
            trendsDataLogic(props),
            ['display', 'indexedResults', 'isTrends', 'trendsFilter'],
        ],
        actions: [
            sidePanelStateLogic,
            ['openSidePanel', 'closeSidePanel'],
            insightLogic(props),
            ['saveInsightSuccess'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setActiveCreation'],
        ],
    })),
    actions({
        explainClicked: true,
        requestConsent: true,
        approveConsent: true,
        dismissConsent: true,
        startInvestigation: true,
        investigationEnded: true,
        explainChartToolCompleted: (
            toolCallId: string,
            input: Record<string, unknown> | null,
            output: Record<string, unknown> | null
        ) => ({ toolCallId, input, output }),
        setInvestigationStream: (streamKey: string) => ({ streamKey }),
        receiveStory: (story: ExplainChartData, query: Node | null) => ({ story, query }),
        showStory: true,
        hideStory: true,
        forgetStory: true,
        askFollowUp: (page: StoryPage, step: number) => ({ page, step }),
        setFollowUpContext: (item: AttachedContextItem) => ({ item }),
    }),
    reducers({
        consentRequested: [
            false,
            {
                requestConsent: () => true,
                approveConsent: () => false,
                dismissConsent: () => false,
            },
        ],
        investigating: [
            false,
            {
                startInvestigation: () => true,
                investigationEnded: () => false,
                receiveStory: () => false,
                forgetStory: () => false,
            },
        ],
        investigationStreamKey: [
            null as string | null,
            {
                startInvestigation: () => null,
                setInvestigationStream: (_, { streamKey }) => streamKey,
            },
        ],
        story: [
            null as ExplainChartData | null,
            {
                receiveStory: (_, { story }) => story,
                forgetStory: () => null,
            },
        ],
        storyQuery: [
            null as Node | null,
            {
                receiveStory: (_, { query }) => query,
                forgetStory: () => null,
            },
        ],
        followUpContext: [
            null as AttachedContextItem | null,
            {
                setFollowUpContext: (_, { item }) => item,
                receiveStory: () => null,
                hideStory: () => null,
                forgetStory: () => null,
            },
        ],
        storyShown: [
            false,
            {
                receiveStory: () => true,
                showStory: () => true,
                hideStory: () => false,
                forgetStory: () => false,
            },
        ],
    }),
    selectors(({ props }) => ({
        explainAvailable: [
            (s) => [s.featureFlags, s.effectivePhaiView, s.isTrends, s.display, s.insight],
            (
                featureFlags: FeatureFlagsSet,
                effectivePhaiView: PhaiViewMode,
                isTrends: boolean,
                display: ChartDisplayType | null | undefined,
                insight: insightLogicValues['insight']
            ): boolean =>
                !!featureFlags[FEATURE_FLAGS.EXPLAIN_CHART] &&
                effectivePhaiView === 'new' &&
                isTrends &&
                isOverTime(display) &&
                !!insight.short_id &&
                !props.filtersOverride &&
                !props.variablesOverride,
        ],
        unsavedDataChanges: [
            (s) => [s.savedInsight, s.query],
            (savedInsight: insightLogicValues['savedInsight'], query: Node | null): boolean =>
                dataDiffers(savedInsight.query, query),
        ],
        storyOutdated: [
            (s) => [s.story, s.storyQuery, s.query],
            (story: ExplainChartData | null, storyQuery: Node | null, query: Node | null): boolean =>
                !!story && dataDiffers(storyQuery, query),
        ],
        storyVisible: [
            (s) => [s.story, s.storyShown, s.storyOutdated],
            (story: ExplainChartData | null, storyShown: boolean, storyOutdated: boolean): boolean =>
                !!story && storyShown && !storyOutdated,
        ],
        explainDisabledReason: [
            (s) => [s.story, s.storyOutdated, s.unsavedDataChanges],
            (story: ExplainChartData | null, storyOutdated: boolean, unsavedDataChanges: boolean): string | null =>
                (!story || storyOutdated) && unsavedDataChanges ? 'Save your changes to explain this version' : null,
        ],
        investigationPrompt: [
            (s) => [s.insight],
            (insight: insightLogicValues['insight']): string => {
                return `Explain why the insight ${insight.short_id} looks the way it does. I'm on the insight page, which opens your explain-chart result beside the chart as soon as the tool returns, so skip render-ui. In the chat, reply with one sentence naming the moment to read first, by its number and title. Leave the other findings to the explanation, and don't offer follow-up actions.`
            },
        ],
        storySeriesKey: [
            (s) => [s.story, s.indexedResults],
            (story: ExplainChartData | null, indexedResults: IndexedTrendResult[]): string | null => {
                if (!story) {
                    return null
                }
                const rendered = indexedResults.find((result) => result.seriesIndex === story.seriesIndex)
                return String(rendered?.id ?? story.seriesIndex)
            },
        ],
        formatValue: [
            (s) => [s.trendsFilter, s.baseCurrency],
            (trendsFilter: TrendsFilter | null | undefined, baseCurrency: teamLogicValues['baseCurrency']) =>
                (value: number): string =>
                    formatAggregationAxisValue(trendsFilter, value, baseCurrency),
        ],
    })),
    listeners(({ actions, values, cache }) => ({
        explainClicked: () => {
            if (values.explainDisabledReason) {
                return
            }
            if (values.storyVisible) {
                actions.hideStory()
            } else if (values.story) {
                actions.showStory()
            } else if (!values.dataProcessingAccepted) {
                actions.requestConsent()
            } else {
                actions.startInvestigation()
            }
        },
        approveConsent: () => {
            actions.startInvestigation()
        },
        startInvestigation: () => {
            posthog.capture('explain chart investigation started')
            cache.disposables.add(
                () => {
                    const listenerId = `explain-chart-investigation-${values.insight.short_id}`
                    const endIfOurs = ({ streamKey }: { streamKey: string }): void => {
                        if (values.investigationStreamKey === null || streamKey === values.investigationStreamKey) {
                            actions.investigationEnded()
                        }
                    }
                    toolStreamEventsLogic.actions.registerToolListener(listenerId, {
                        tools: '*',
                        onEvent: (event) => {
                            if (values.investigationStreamKey === null) {
                                actions.setInvestigationStream(event.streamKey)
                            }
                            if (
                                event.streamKey === values.investigationStreamKey &&
                                event.toolName === 'explain-chart' &&
                                event.phase === 'completed'
                            ) {
                                actions.explainChartToolCompleted(
                                    event.toolCallId,
                                    resolveToolCall(event.invocation).innerInput ?? null,
                                    getToolOutputRecord({
                                        rawOutput: event.invocation.output,
                                        status: event.invocation.status,
                                    })
                                )
                            }
                        },
                        onTurnComplete: endIfOurs,
                        onRunTerminal: endIfOurs,
                    })
                    return () => toolStreamEventsLogic.actions.deregisterToolListener(listenerId)
                },
                'investigation',
                { pauseOnPageHidden: false }
            )
            actions.openSidePanel(SidePanelTab.Max, autoRunMaxPrompt(values.investigationPrompt))
        },
        setActiveCreation: ({ creation }) => {
            if (values.investigating && values.investigationStreamKey === null) {
                actions.setInvestigationStream(creation.streamKey)
            }
        },
        setInvestigationStream: ({ streamKey }) => {
            cache.disposables.add(() => runStreamLogic({ streamKey }).mount(), 'investigationStream', {
                pauseOnPageHidden: false,
            })
        },
        investigationEnded: () => {
            cache.disposables.dispose('investigation')
            cache.disposables.dispose('investigationStream')
        },
        explainChartToolCompleted: ({ toolCallId, input, output }) => {
            cache.appliedToolCallIds ??= new Set<string>()
            if (cache.appliedToolCallIds.has(toolCallId)) {
                return
            }
            const story = explainChartStoryFor(values.insight, input, output)
            if (!story) {
                return
            }
            cache.appliedToolCallIds.add(toolCallId)
            actions.receiveStory(story, values.savedInsight.query ?? null)
            actions.closeSidePanel(SidePanelTab.Max)
        },
        askFollowUp: ({ page, step }) => {
            posthog.capture('explain chart follow-up opened', { page_index: step })
            actions.setFollowUpContext(followUpContextFor(values.insight, page, step))
            actions.openSidePanel(SidePanelTab.Max)
        },
        receiveStory: ({ story }) => {
            posthog.capture('explain chart story shown', { chapters: story.chapters.length })
        },
        saveInsightSuccess: () => {
            if (values.storyOutdated) {
                actions.forgetStory()
            }
        },
    })),
])

const EXPLAINABLE_DISPLAYS: ChartDisplayType[] = [
    ChartDisplayType.ActionsLineGraph,
    ChartDisplayType.ActionsBar,
    ChartDisplayType.ActionsUnstackedBar,
    ChartDisplayType.ActionsAreaGraph,
    ChartDisplayType.ActionsStackedBar,
]

function dataDiffers(a: Node | null | undefined, b: Node | null | undefined): boolean {
    return !!a && !!b && !compareQuery(a, b, { ignoreVisualizationOnlyChanges: true })
}

function isOverTime(display: ChartDisplayType | null | undefined): boolean {
    return !display || EXPLAINABLE_DISPLAYS.includes(display)
}
