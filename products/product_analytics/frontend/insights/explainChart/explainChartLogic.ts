export const explainChartLogic: LogicWrapper<explainChartLogicType> = kea<explainChartLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'explainChart', 'explainChartLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            maxGlobalLogic,
            ['effectivePhaiView'],
            aiConsentLogic,
            ['dataProcessingAccepted'],
            insightLogic(props),
            ['insight'],
            insightDataLogic(props),
            ['queryChanged'],
            teamLogic,
            ['baseCurrency'],
            trendsDataLogic(props),
            ['display', 'isTrends', 'trendsFilter'],
        ],
        actions: [
            sidePanelStateLogic,
            ['openSidePanel', 'closeSidePanel'],
            insightLogic(props),
            ['saveInsightSuccess'],
        ],
    })),
    actions({
        explainClicked: true,
        requestConsent: true,
        approveConsent: true,
        dismissConsent: true,
        startInvestigation: true,
        explainChartToolCompleted: (input: Record<string, unknown> | null, output: Record<string, unknown> | null) => ({
            input,
            output,
        }),
        receiveStory: (story: ExplainChartData) => ({ story }),
        showStory: true,
        hideStory: true,
        forgetStory: true,
        askFollowUp: (page: StoryPage, step: number) => ({ page, step }),
        setFollowUpContext: (item: AttachedContextItem) => ({ item }),
    }),
    reducers({
        consentRequested: [
            false,
            {
                requestConsent: () => true,
                approveConsent: () => false,
                dismissConsent: () => false,
            },
        ],
        investigating: [
            false,
            {
                startInvestigation: () => true,
                receiveStory: () => false,
                forgetStory: () => false,
            },
        ],
        story: [
            null as ExplainChartData | null,
            {
                receiveStory: (_, { story }) => story,
                forgetStory: () => null,
            },
        ],
        followUpContext: [
            null as AttachedContextItem | null,
            {
                setFollowUpContext: (_, { item }) => item,
                receiveStory: () => null,
                hideStory: () => null,
                forgetStory: () => null,
            },
        ],
        storyShown: [
            false,
            {
                receiveStory: () => true,
                showStory: () => true,
                hideStory: () => false,
                forgetStory: () => false,
            },
        ],
    }),
    selectors(({ props }) => ({
        explainAvailable: [
            (s) => [s.featureFlags, s.effectivePhaiView, s.isTrends, s.display, s.insight, s.queryChanged],
            (
                featureFlags: FeatureFlagsSet,
                effectivePhaiView: PhaiViewMode,
                isTrends: boolean,
                display: ChartDisplayType | null | undefined,
                insight: insightLogicValues['insight'],
                queryChanged: boolean
            ): boolean =>
                !!featureFlags[FEATURE_FLAGS.EXPLAIN_CHART] &&
                // Only the PostHog AI sandbox agent can call explain-chart.
                effectivePhaiView === 'new' &&
                isTrends &&
                isOverTime(display) &&
                // explain-chart reads the saved insight, so the chart on screen has to be that insight.
                !!insight.short_id &&
                !queryChanged &&
                !props.filtersOverride &&
                !props.variablesOverride,
        ],
        investigationPrompt: [
            (s) => [s.insight],
            (insight: insightLogicValues['insight']): string => {
                const name = insight.name || insight.derived_name || 'this chart'
                return `Explain why the "${name}" insight (${insight.short_id}) looks the way it does. I'm on the insight page, which opens your explain-chart result beside the chart as soon as the tool returns, so skip render-ui. In the chat, just tell me which moment to read first, by its number and title.`
            },
        ],
        formatValue: [
            (s) => [s.trendsFilter, s.baseCurrency],
            (trendsFilter: TrendsFilter | null | undefined, baseCurrency: teamLogicValues['baseCurrency']) =>
                (value: number): string =>
                    formatAggregationAxisValue(trendsFilter, value, baseCurrency),
        ],
    })),
    listeners(({ actions, values }) => ({
        explainClicked: () => {
            if (values.storyShown) {
                actions.hideStory()
            } else if (values.story) {
                actions.showStory()
            } else if (!values.dataProcessingAccepted) {
                actions.requestConsent()
            } else {
                actions.startInvestigation()
            }
        },
        approveConsent: () => {
            actions.startInvestigation()
        },
        startInvestigation: () => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('explain chart investigation started')
            actions.openSidePanel(SidePanelTab.Max, autoRunMaxPrompt(values.investigationPrompt))
        },
        explainChartToolCompleted: ({ input, output }) => {
            const story = explainChartStoryFor(values.insight, input, output)
            if (!story) {
                return
            }
            const startedHere = values.investigating
            actions.receiveStory(story)
            if (startedHere) {
                actions.closeSidePanel(SidePanelTab.Max)
            }
        },
        askFollowUp: ({ page, step }) => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('explain chart follow-up opened', { page_index: step })
            actions.setFollowUpContext(followUpContextFor(values.insight, page, step))
            actions.openSidePanel(SidePanelTab.Max)
        },
        receiveStory: ({ story }) => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('explain chart story shown', { chapters: story.chapters.length })
        },
        saveInsightSuccess: () => {
            actions.forgetStory()
        },
    })),
])

function isOverTime(display: ChartDisplayType | null | undefined): boolean {
    // A cumulative line shows running totals, so a step on it is not a change in activity.
    return (
        !display ||
        (!NON_TIME_SERIES_DISPLAY_TYPES.includes(display) && display !== ChartDisplayType.ActionsLineGraphCumulative)
    )
}
