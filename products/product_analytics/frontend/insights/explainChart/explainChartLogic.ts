export const explainChartLogic: LogicWrapper<explainChartLogicType> = kea<explainChartLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'explainChart', 'explainChartLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            insightLogic(props),
            ['insight'],
            insightVizDataLogic(props),
            ['insightDataLoading', 'querySource'],
            teamLogic,
            ['baseCurrency'],
            trendsDataLogic(props),
            [
                'display',
                'getTrendsHidden',
                'incompletenessOffsetFromEnd',
                'indexedResults',
                'interval',
                'isTrends',
                'trendsFilter',
            ],
        ],
        actions: [insightVizDataLogic(props), ['loadDataSuccess']],
    })),
    actions({
        openExplain: true,
        closeExplain: true,
    }),
    loaders(({ cache, values }) => ({
        evidenceResults: [
            null as EvidenceResults | null,
            {
                loadEvidence: async (_: void, breakpoint): Promise<EvidenceResults | null> => {
                    const queries = values.evidenceQueries
                    if (!queries || !values.moments.length) {
                        return null
                    }
                    // A new search, a closed explanation or leaving the insight stops the queries of the last search.
                    const abortController = new AbortController()
                    cache.disposables.add(() => () => abortController.abort(), 'explainEvidence', {
                        pauseOnPageHidden: false,
                    })
                    const options = { signal: abortController.signal }
                    // A split that fails leaves the others to explain the change.
                    const [breakdowns, people] = await Promise.all([
                        Promise.all(
                            queries.breakdowns.map(async ({ property, query }) => {
                                try {
                                    const response = await performQuery(query, options)
                                    return { property, query, rows: (response.results ?? []) as EvidenceRow[] }
                                } catch {
                                    return null
                                }
                            })
                        ),
                        // Only a peak reads the people count.
                        queries.people && values.moments.some((moment) => moment.kind === 'peak')
                            ? performQuery(queries.people, options)
                                  .then((response) => ({
                                      query: queries.people as NonNullable<EvidenceQueries['people']>,
                                      data: ((response.results?.[0] as EvidenceRow | undefined)?.data ??
                                          []) as number[],
                                  }))
                                  .catch(() => null)
                            : null,
                    ])
                    breakpoint()
                    return {
                        breakdowns: breakdowns.filter(
                            (breakdown): breakdown is NonNullable<typeof breakdown> => !!breakdown
                        ),
                        people,
                    }
                },
            },
        ],
        modelCauses: [
            null as Record<string, ModelCause> | null,
            {
                loadModelCauses: async (_: void, breakpoint): Promise<Record<string, ModelCause> | null> => {
                    const series = values.explainedSeries
                    const facts = values.momentFacts
                    if (!series || !facts.length) {
                        return null
                    }
                    let causes: Record<string, ModelCause> | null = null
                    try {
                        const response = await insightsExplainCreate(String(getCurrentTeamId()), {
                            series_label: series.label.slice(0, 200) || 'Series',
                            insight_name: (values.insight.name || values.insight.derived_name || '').slice(0, 400),
                            overview: plainStoryText(values.overview).slice(0, 600),
                            chapters: facts.slice(0, 8).map(({ moment, facts, evidence }) => ({
                                id: moment.id,
                                title: moment.title.slice(0, 200),
                                summary: plainStoryText(facts).slice(0, 600),
                                evidence: evidence.slice(0, 6).map((item) => plainStoryText(item.text).slice(0, 600)),
                            })),
                        })
                        causes = Object.fromEntries(
                            response.chapters.map(({ id, cause, confidence }) => [id, { cause, confidence }])
                        )
                    } catch {
                        // The steps keep the causes that their evidence shows on its own.
                        causes = null
                    }
                    breakpoint()
                    // Causes read from the facts of an older chart do not belong to this one.
                    if (values.momentFacts !== facts) {
                        return null
                    }
                    return causes
                },
            },
        ],
    })),
    reducers({
        explainOpen: [
            false,
            {
                openExplain: () => true,
                closeExplain: () => false,
            },
        ],
        // Causes belong to the facts they were read from, and new evidence means new facts.
        modelCauses: {
            loadEvidence: () => null,
        },
    }),
    selectors({
        formatValue: [
            (s) => [s.trendsFilter, s.baseCurrency],
            (trendsFilter: TrendsFilter | null | undefined, baseCurrency: teamLogicValues['baseCurrency']) =>
                (value: number): string =>
                    formatAggregationAxisValue(trendsFilter, value, baseCurrency),
        ],
        explainedSeries: [
            (s) => [s.indexedResults, s.getTrendsHidden, s.display, s.isTrends, s.querySource],
            (
                indexedResults: IndexedTrendResult[],
                getTrendsHidden: trendsDataLogicValues['getTrendsHidden'],
                display: ChartDisplayType | null | undefined,
                isTrends: boolean,
                querySource: insightVizDataLogicValues['querySource']
            ): ExplainedSeries | null => {
                // A cumulative line shows running totals, which the moments would read as growth every day.
                if (
                    !isTrends ||
                    (display &&
                        (NON_TIME_SERIES_DISPLAY_TYPES.includes(display) ||
                            display === ChartDisplayType.ActionsLineGraphCumulative))
                ) {
                    return null
                }
                const shown = (indexedResults ?? []).filter(
                    (result) => result.compare_label !== 'previous' && !getTrendsHidden(result) && !!result.days?.length
                )
                if (!shown.length) {
                    return null
                }
                // The explanation follows the biggest series on the chart.
                const sum = (result: IndexedTrendResult): number =>
                    result.data.reduce((total, value) => total + value, 0)
                const lead = shown.reduce((best, result) => (sum(result) > sum(best) ? result : best))
                const { node } = getResultSeries(querySource, lead)
                return {
                    index: lead.id,
                    label: (node && getResultSeriesCustomName(node)) || lead.label,
                    queryIndex: getResultOrder(lead),
                    data: lead.data,
                    days: lead.days,
                }
            },
        ],
        moments: [
            (s) => [s.explainedSeries, s.interval, s.incompletenessOffsetFromEnd],
            (
                explainedSeries: ExplainedSeries | null,
                interval: IntervalType | null | undefined,
                incompletenessOffsetFromEnd: number
            ): ChartMoment[] =>
                explainedSeries
                    ? findChartMoments(explainedSeries, {
                          interval: interval ?? 'day',
                          incompletePoints: -incompletenessOffsetFromEnd,
                      })
                    : [],
        ],
        overview: [
            (s) => [s.explainedSeries, s.interval, s.incompletenessOffsetFromEnd, s.formatValue],
            (
                explainedSeries: ExplainedSeries | null,
                interval: IntervalType | null | undefined,
                incompletenessOffsetFromEnd: number,
                formatValue: (value: number) => string
            ): string =>
                explainedSeries?.data.some((value) => value !== 0)
                    ? overviewFacts(explainedSeries.data, {
                          interval: interval ?? 'day',
                          lastPointInProgress: incompletenessOffsetFromEnd < 0,
                          formatValue,
                      })
                    : '',
        ],
        explainAvailable: [
            (s) => [s.featureFlags, s.overview],
            (featureFlags: FeatureFlagsSet, overview: string): boolean =>
                !!featureFlags[FEATURE_FLAGS.EXPLAIN_CHART] && !!overview,
        ],
        evidenceQueries: [
            (s) => [s.querySource, s.explainedSeries],
            (
                querySource: insightVizDataLogicValues['querySource'],
                explainedSeries: ExplainedSeries | null
            ): EvidenceQueries | null =>
                explainedSeries ? buildEvidenceQueries(querySource, explainedSeries.queryIndex) : null,
        ],
        momentFacts: [
            (s) => [
                s.moments,
                s.explainedSeries,
                s.evidenceResults,
                s.interval,
                s.incompletenessOffsetFromEnd,
                s.formatValue,
            ],
            (
                moments: ChartMoment[],
                explainedSeries: ExplainedSeries | null,
                evidenceResults: EvidenceResults | null,
                interval: IntervalType | null | undefined,
                incompletenessOffsetFromEnd: number,
                formatValue: (value: number) => string
            ): MomentFacts[] =>
                explainedSeries
                    ? moments.map((moment) => ({
                          moment,
                          // The same facts the explanation shows, so the model reads what the person reads.
                          facts: chapterFacts(explainedSeries.data, explainedSeries.days, moment.range, {
                              interval: interval ?? 'day',
                              lastPointInProgress: incompletenessOffsetFromEnd < 0,
                              formatValue,
                          }),
                          evidence: evidenceResults
                              ? evidenceForMoment(moment, evidenceResults, {
                                    values: explainedSeries.data,
                                    completePoints: explainedSeries.data.length + incompletenessOffsetFromEnd,
                                    interval: interval ?? 'day',
                                    formatValue,
                                })
                              : [],
                      }))
                    : [],
        ],
        explainedChapters: [
            (s) => [s.momentFacts, s.modelCauses],
            (momentFacts: MomentFacts[], modelCauses: Record<string, ModelCause> | null): ExplainedChapter[] =>
                momentFacts.map(({ moment, evidence }) => {
                    const model = modelCauses?.[moment.id] ?? null
                    const cause = chapterCause(moment, evidence, model)
                    return { moment, evidence, cause, unclear: isUnclear(cause, model) }
                }),
        ],
        // The question for PostHog AI about the first step that no known cause explains.
        lookDeeperQuestion: [
            (s) => [s.explainedChapters, s.modelCausesLoading, s.evidenceResultsLoading],
            (
                explainedChapters: ExplainedChapter[],
                modelCausesLoading: boolean,
                evidenceResultsLoading: boolean
            ): string | null => {
                const step = explainedChapters.find((chapter) => chapter.unclear)
                return step && !modelCausesLoading && !evidenceResultsLoading
                    ? `Why does this chart show "${step.moment.title}"?`
                    : null
            },
        ],
        headline: [
            (s) => [s.explainedChapters],
            (explainedChapters: ExplainedChapter[]): string => headlineText(explainedChapters),
        ],
        explainChartData: [
            (s) => [
                s.explainedSeries,
                s.querySource,
                s.indexedResults,
                s.insight,
                s.incompletenessOffsetFromEnd,
                s.headline,
                s.explainedChapters,
            ],
            (
                explainedSeries: ExplainedSeries | null,
                querySource: insightVizDataLogicValues['querySource'],
                indexedResults: IndexedTrendResult[],
                insight: insightLogicValues['insight'],
                incompletenessOffsetFromEnd: number,
                headline: string,
                explainedChapters: ExplainedChapter[]
            ): ExplainChartData | null => {
                if (!explainedSeries || !querySource) {
                    return null
                }
                return {
                    query: querySource as unknown as StoryTrendsQuery,
                    results: indexedResults.map(({ label, data, days }) => ({
                        label: label ?? undefined,
                        data,
                        days,
                    })),
                    seriesIndex: explainedSeries.index,
                    insightName: insight.name || insight.derived_name || null,
                    lastPointInProgress: incompletenessOffsetFromEnd < 0,
                    headline,
                    chapters: explainedChapters.map(({ moment, evidence, cause }): StoryChapter => {
                        return {
                            title: moment.title,
                            range: moment.range,
                            summary: null,
                            cause: cause ? causeSentence(cause) : null,
                            confidence: cause?.confidence ?? null,
                            confidenceReason: null,
                            evidence: evidence.map((item) => ({
                                text: item.text,
                                url: null,
                                query: item.query as Record<string, unknown> | null,
                            })),
                        }
                    }),
                }
            },
        ],
    }),
    listeners(({ actions, cache, values }) => ({
        openExplain: () => {
            posthog.capture('explain chart opened', {
                moments: values.moments.map((moment) => moment.kind),
                can_search_for_cause: !!values.evidenceQueries,
            })
            actions.loadEvidence()
        },
        closeExplain: () => {
            cache.disposables.dispose('explainEvidence')
            posthog.capture('explain chart closed', { chapters: values.moments.length })
        },
        loadDataSuccess: () => {
            if (values.explainOpen) {
                actions.loadEvidence()
            }
        },
        loadEvidenceSuccess: () => {
            if (values.explainOpen) {
                actions.loadModelCauses()
            }
        },
    })),
])
