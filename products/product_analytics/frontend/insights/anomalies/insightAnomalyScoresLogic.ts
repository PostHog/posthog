import { MakeLogicType, afterMount, connect, kea, key, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { projectLogic } from 'scenes/projectLogic'

import { signalsAnomaliesInsightRetrieve } from 'products/signals/frontend/generated/api'
import type { AnomalyInsightSeriesApi } from 'products/signals/frontend/generated/api.schemas'

import { scoreHistoryRange } from './anomalyScorePoints'

export interface InsightAnomalyScoresLogicProps {
    insightId: number
    /** The range of the chart. Without it, the API default applies. */
    dateFrom?: string | null
    dateTo?: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightAnomalyScoresLogicValues {
    currentProjectId: number | null // projectLogic
    scoredSeries: AnomalyInsightSeriesApi[]
    scoredSeriesLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightAnomalyScoresLogicActions {
    loadScoredSeries: () => any
    loadScoredSeriesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadScoredSeriesSuccess: (
        scoredSeries: AnomalyInsightSeriesApi[],
        payload?: any
    ) => {
        scoredSeries: AnomalyInsightSeriesApi[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightAnomalyScoresLogicMeta {
    key: string
}

export type insightAnomalyScoresLogicType = MakeLogicType<
    insightAnomalyScoresLogicValues,
    insightAnomalyScoresLogicActions,
    InsightAnomalyScoresLogicProps,
    insightAnomalyScoresLogicMeta
>

export const insightAnomalyScoresLogic = kea<insightAnomalyScoresLogicType>([
    path((key) => [
        'products',
        'product_analytics',
        'frontend',
        'insights',
        'anomalies',
        'insightAnomalyScoresLogic',
        key,
    ]),
    props({} as InsightAnomalyScoresLogicProps),
    key(({ insightId, dateFrom, dateTo }) => `${insightId}-${dateFrom ?? ''}-${dateTo ?? ''}`),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    loaders(({ props, values }) => ({
        scoredSeries: [
            [] as AnomalyInsightSeriesApi[],
            {
                loadScoredSeries: async () => {
                    if (values.currentProjectId == null) {
                        return []
                    }
                    try {
                        const response = await signalsAnomaliesInsightRetrieve(String(values.currentProjectId), {
                            insight_id: props.insightId,
                            include_buckets: true,
                            ...scoreHistoryRange(props.dateFrom, props.dateTo),
                        })
                        return response.series
                    } catch {
                        // The marks are an extra on the chart. A 404 from the anomaly search gate, or any other
                        // failure, leaves the chart without them and shows no error.
                        return []
                    }
                },
            },
        ],
    })),
    afterMount(({ actions }) => {
        actions.loadScoredSeries()
    }),
])
