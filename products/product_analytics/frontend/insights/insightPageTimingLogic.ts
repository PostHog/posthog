type PageStatus = 'success' | 'failure' | 'cancelled'

interface PageLoad {
    startedAt: number
    interactionId: string
    allowMetadataResult: boolean
    metadataLoadedAt?: number
    dataStatus?: 'success' | 'failure'
    isCached?: boolean
}

function responseStatus(response: AnyResponseType | Partial<InsightModel> | null | undefined): PageLoad['dataStatus'] {
    if (!response || typeof response !== 'object') {
        return undefined
    }
    if (('error' in response && response.error) || response.query_status?.error) {
        return 'failure'
    }
    return isCompleteResponse(response) ? 'success' : undefined
}

