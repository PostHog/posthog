export const insightPageTimingLogic: LogicWrapper<insightPageTimingLogicType> = kea<insightPageTimingLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'insightPageTimingLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [insightLogic(props), ['insight', 'insightLoading'], teamLogic, ['currentTeamId']],
        actions: [
            insightLogic(props),
            ['loadInsightSuccess as metadataLoaded', 'loadInsightFailure as metadataFailed'],
            dataNodeLogic({ key: insightVizDataNodeKey(props) } as DataNodeLogicProps),
            ['loadDataSuccess', 'loadDataFailure', 'setResponseSuccess', 'cancelQuery'],
        ],
    })),
    actions({
        startPageLoad: (startedAt: number, allowMetadataResult: boolean) => ({ startedAt, allowMetadataResult }),
        recordMetadata: (insight: Partial<InsightModel>) => ({ insight }),
        recordResponse: (response: AnyResponseType | null | undefined) => ({ response }),
        finishIfReady: true,
        finishPageLoad: (status: PageStatus) => ({ status }),
    }),
    listeners(({ actions, cache, values }) => ({
        startPageLoad: ({ startedAt, allowMetadataResult }) => {
            actions.finishPageLoad('cancelled')
            cache.pageLoad = { startedAt, allowMetadataResult, interactionId: uuid() } satisfies PageLoad
            if (!values.insightLoading && values.insight.id) {
                actions.recordMetadata(values.insight)
            }
        },
        metadataLoaded: ({ insight }) => actions.recordMetadata(insight),
        metadataFailed: () => actions.finishPageLoad('failure'),
        recordMetadata: ({ insight }) => {
            const page: PageLoad | undefined = cache.pageLoad
            if (!page) {
                return
            }
            page.metadataLoadedAt = performance.now()
            if (page.allowMetadataResult) {
                const status = responseStatus(insight)
                if (status) {
                    page.dataStatus = status
                    page.isCached = insight.is_cached
                }
            }
            actions.finishIfReady()
        },
        loadDataSuccess: ({ response }) => actions.recordResponse(response),
        setResponseSuccess: ({ response }) => actions.recordResponse(response),
        recordResponse: ({ response }) => {
            const page: PageLoad | undefined = cache.pageLoad
            if (!page) {
                return
            }
            const status = responseStatus(response)
            if (status) {
                page.dataStatus = status
                page.isCached = !!response && 'is_cached' in response && !!response.is_cached
                actions.finishIfReady()
            }
        },
        loadDataFailure: () => {
            const page: PageLoad | undefined = cache.pageLoad
            if (page) {
                page.dataStatus = 'failure'
                actions.finishIfReady()
            }
        },
        cancelQuery: () => actions.finishPageLoad('cancelled'),
        finishIfReady: () => {
            const page: PageLoad | undefined = cache.pageLoad
            if (page?.metadataLoadedAt !== undefined && page.dataStatus) {
                actions.finishPageLoad(page.dataStatus)
            }
        },
        finishPageLoad: ({ status }) => {
            const page: PageLoad | undefined = cache.pageLoad
            if (!page) {
                return
            }
            cache.pageLoad = undefined
            const elapsed = Math.floor(performance.now() - page.startedAt)
            const payload: PageLoadTimeToSeeData = {
                type: 'page_load',
                context: 'saved-insight',
                scene: Scene.Insight,
                team_id: values.currentTeamId,
                primary_interaction_id: page.interactionId,
                status,
                time_to_see_data_ms: elapsed,
                time_since_mount_ms: elapsed,
                metadata_load_ms:
                    page.metadataLoadedAt === undefined
                        ? undefined
                        : Math.floor(page.metadataLoadedAt - page.startedAt),
                insights_fetched: status === 'success' ? 1 : 0,
                insights_fetched_cached: status === 'success' && page.isCached ? 1 : 0,
                is_primary_interaction: true,
            }
            posthog.capture('time to see data', { ...payload, $update_person_last_seen_at: false })
        },
    })),
])
