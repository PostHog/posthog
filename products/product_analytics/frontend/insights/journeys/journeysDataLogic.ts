const clamp = (value: number, bounds: { min: number; max: number }): number =>
    Math.min(Math.max(value, bounds.min), bounds.max)

export const journeysDataLogic = kea<journeysDataLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps(DEFAULT_JOURNEYS_LOGIC_KEY)),
    path((key) => ['products', 'product_analytics', 'insights', 'journeys', 'journeysDataLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            insightVizDataLogic(props),
            ['insightData', 'pathsV2Filter', 'theme', 'querySource as vizQuerySource'],
        ],
        actions: [insightVizDataLogic(props), ['updateInsightFilter']],
    })),
    actions({
        setStepSources: (stepSources: PathsV2StepSource[]) => ({ stepSources }),
        setStepSourceEvent: (index: number, event: string) => ({ index, event }),
        setStepSourceNamingProperty: (index: number, namingProperty: string) => ({ index, namingProperty }),
        addStepSource: (event: string) => ({ event }),
        removeStepSource: (index: number) => ({ index }),
        setExcludedLabels: (source: PathsV2StepSource, labels: string[]) => ({ source, labels }),
        removeExcludedItem: (item: PathsV2Item) => ({ item }),
        setDraftMaxSteps: (maxSteps: number | null) => ({ maxSteps }),
        setDraftMaxRowsPerStep: (maxRowsPerStep: number | null) => ({ maxRowsPerStep }),
        commitGridSize: true,
        cardClicked: (stepIndex: number, row: JourneyGridRow) => ({ stepIndex, row }),
        ribbonClicked: (ribbon: JourneyGridRibbon) => ({ ribbon }),
        cardHovered: (stepIndex: number, row: JourneyGridRow) => ({ stepIndex, row }),
        ribbonHovered: (ribbon: JourneyGridRibbon) => ({ ribbon }),
        gridLeft: true,
        setActiveChain: (chain: PathsV2Item[] | null) => ({ chain }),
    }),
    reducers({
        // Grid-size inputs commit on blur/enter rather than per keystroke; null means untouched,
        // so external filter changes keep showing through until the user edits.
        draftMaxSteps: [
            null as number | null,
            {
                setDraftMaxSteps: (_, { maxSteps }) => maxSteps,
            },
        ],
        draftMaxRowsPerStep: [
            null as number | null,
            {
                setDraftMaxRowsPerStep: (_, { maxRowsPerStep }) => maxRowsPerStep,
            },
        ],
        // The hover-preview chain (anchored mode). It stays active while the pointer stays on the
        // chain's own cards and ribbons, so the pointer can travel from a ribbon onto a chain card
        // and the card's click opens the chain's persons rather than the union's.
        activeChain: [
            null as PathsV2Item[] | null,
            {
                setActiveChain: (_, { chain }) => chain,
                updateInsightFilter: () => null,
            },
        ],
    }),
    selectors({
        results: [
            (s) => [s.insightData],
            (insightData: Record<string, any> | null): PathsV2Results | null => {
                const results = insightData?.result ?? insightData?.results
                return results && Array.isArray(results.steps) ? (results as PathsV2Results) : null
            },
        ],
        isAnchored: [
            (s) => [s.pathsV2Filter],
            (pathsV2Filter: PathsV2Filter | null): boolean => !!pathsV2Filter?.anchor,
        ],
        gridModel: [
            (s) => [s.results],
            (results: PathsV2Results | null): JourneyGridModel => buildJourneyGridModel(results),
        ],
        stepSources: [
            (s) => [s.pathsV2Filter],
            (pathsV2Filter: PathsV2Filter | null): PathsV2StepSource[] =>
                pathsV2Filter?.stepSources ?? DEFAULT_STEP_SOURCES,
        ],
        anchor: [
            (s) => [s.pathsV2Filter],
            (pathsV2Filter: PathsV2Filter | null): PathsV2Anchor | null => pathsV2Filter?.anchor ?? null,
        ],
        excludedItems: [
            (s) => [s.pathsV2Filter],
            (pathsV2Filter: PathsV2Filter | null): PathsV2Item[] => pathsV2Filter?.excludedItems ?? [],
        ],
        prefixes: [(s) => [s.results], (results: PathsV2Results | null): PathsV2Prefix[] => results?.prefixes ?? []],
        prefixCounts: [
            (s) => [s.prefixes],
            (prefixes: PathsV2Prefix[]): Map<string, number> =>
                new Map(prefixes.map((prefix) => [chainKey(prefix.items), prefix.count])),
        ],
        activeChainHighlight: [
            (s) => [s.activeChain, s.prefixCounts],
            (activeChain: PathsV2Item[] | null, prefixCounts: Map<string, number>): JourneyChainHighlight | null => {
                if (!activeChain || activeChain.length === 0) {
                    return null
                }
                const countByCardKey: Record<string, number> = {}
                const ribbonKeys = new Set<string>()
                for (let position = 0; position < activeChain.length; position++) {
                    const count = prefixCounts.get(chainKey(activeChain.slice(0, position + 1)))
                    if (count === undefined) {
                        // A sub-chain fell beyond the carried prefix rows: no honest preview exists.
                        return null
                    }
                    countByCardKey[chainCardKey(position, activeChain[position])] = count
                    if (position > 0) {
                        ribbonKeys.add(
                            `${position - 1}:${journeyItemKey(activeChain[position - 1])}→${journeyItemKey(
                                activeChain[position]
                            )}`
                        )
                    }
                }
                return { chain: activeChain, countByCardKey, ribbonKeys }
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setStepSources: ({ stepSources }) => {
            actions.updateInsightFilter({ stepSources })
        },
        setStepSourceEvent: ({ index, event }) => {
            if (values.stepSources.some((source, i) => i !== index && source.event === event)) {
                lemonToast.info(`${event} is already a step source`)
                return
            }
            // The naming property does not carry over: it usually does not exist on the new event,
            // and a stale one would silently merge all its items under an empty label.
            actions.setStepSources(values.stepSources.map((source, i) => (i === index ? { event } : source)))
        },
        setStepSourceNamingProperty: ({ index, namingProperty }) => {
            actions.setStepSources(
                values.stepSources.map((source, i) =>
                    i === index ? { event: source.event, ...(namingProperty ? { namingProperty } : {}) } : source
                )
            )
        },
        addStepSource: ({ event }) => {
            if (values.stepSources.some((source) => source.event === event)) {
                lemonToast.info(`${event} is already a step source`)
                return
            }
            actions.setStepSources([...values.stepSources, { event }])
        },
        removeStepSource: ({ index }) => {
            actions.setStepSources(values.stepSources.filter((_, i) => i !== index))
        },
        setExcludedLabels: ({ source, labels }) => {
            actions.updateInsightFilter({ excludedItems: withExcludedLabels(values.excludedItems, source, labels) })
        },
        removeExcludedItem: ({ item }) => {
            actions.updateInsightFilter({ excludedItems: values.excludedItems.filter((existing) => existing !== item) })
        },
        commitGridSize: () => {
            const update: Partial<PathsV2Filter> = {}
            if (values.draftMaxSteps !== null) {
                const maxSteps = clamp(values.draftMaxSteps, MAX_STEPS_BOUNDS)
                if (maxSteps !== values.draftMaxSteps) {
                    actions.setDraftMaxSteps(maxSteps)
                }
                if (maxSteps !== (values.pathsV2Filter?.maxSteps ?? undefined)) {
                    update.maxSteps = maxSteps
                }
            }
            if (values.draftMaxRowsPerStep !== null) {
                const maxRowsPerStep = clamp(values.draftMaxRowsPerStep, MAX_ROWS_PER_STEP_BOUNDS)
                if (maxRowsPerStep !== values.draftMaxRowsPerStep) {
                    actions.setDraftMaxRowsPerStep(maxRowsPerStep)
                }
                if (maxRowsPerStep !== (values.pathsV2Filter?.maxRowsPerStep ?? undefined)) {
                    update.maxRowsPerStep = maxRowsPerStep
                }
            }
            if (Object.keys(update).length > 0) {
                actions.updateInsightFilter(update)
            }
        },
        cardClicked: ({ stepIndex, row }) => {
            const openModalFor = (element: PathsV2ElementSelector, title: ReactNode): void => {
                const source = values.vizQuerySource
                if (source?.kind !== NodeKind.PathsV2Query) {
                    return
                }
                openPersonsModal({
                    title,
                    query: { kind: NodeKind.PathsV2ActorsQuery, source: source as PathsV2Query, element },
                })
            }
            if (values.activeChain && isCardOnChain(values.activeChain, stepIndex, row.key)) {
                // The card currently shows this chain's count, so its modal is the chain's people.
                const chain = values.activeChain.slice(0, stepIndex + 1)
                openModalFor({ elementType: PathsV2ElementType.Chain, chain }, journeysChainModalTitle(chain))
                return
            }
            if (row.kind === 'item' && row.item) {
                openModalFor(
                    { elementType: PathsV2ElementType.Node, stepIndex, item: row.item },
                    journeysNodeModalTitle(stepIndex, row.item)
                )
            } else if (row.kind === 'other') {
                openModalFor({ elementType: PathsV2ElementType.Other, stepIndex }, journeysOtherModalTitle(stepIndex))
            } else if (row.kind === 'dropOff') {
                openModalFor(
                    { elementType: PathsV2ElementType.DropOff, stepIndex },
                    journeysDropOffModalTitle(stepIndex)
                )
            }
        },
        ribbonClicked: ({ ribbon }) => {
            const source = values.vizQuerySource
            if (source?.kind !== NodeKind.PathsV2Query) {
                return
            }
            openPersonsModal({
                title: journeysEdgeModalTitle(
                    ribbon.sourceStep,
                    ribbon.sourceItem,
                    ribbon.targetItem,
                    ribbon.anyStepCount
                ),
                query: {
                    kind: NodeKind.PathsV2ActorsQuery,
                    source: source as PathsV2Query,
                    element: {
                        elementType: PathsV2ElementType.Edge,
                        stepIndex: ribbon.sourceStep,
                        source: ribbon.sourceItem ?? undefined,
                        target: ribbon.targetItem ?? undefined,
                    },
                },
            })
        },
        ribbonHovered: ({ ribbon }) => {
            if (!values.isAnchored || !ribbon.sourceItem || !ribbon.targetItem) {
                if (values.activeChain) {
                    actions.setActiveChain(null)
                }
                return
            }
            // Prefixes come count-descending, so the first chain through this ribbon is the most
            // common one: the ribbon pins the chain's last hop, the dominant prefix fills the rest.
            const chain = values.prefixes.find(
                (prefix) =>
                    prefix.items.length === ribbon.sourceStep + 2 &&
                    journeyItemKey(prefix.items[ribbon.sourceStep]) === ribbon.sourceKey &&
                    journeyItemKey(prefix.items[ribbon.sourceStep + 1]) === ribbon.targetKey
            )
            actions.setActiveChain(chain?.items ?? null)
        },
        cardHovered: ({ stepIndex, row }) => {
            if (values.activeChain && !isCardOnChain(values.activeChain, stepIndex, row.key)) {
                actions.setActiveChain(null)
            }
        },
        gridLeft: () => {
            if (values.activeChain) {
                actions.setActiveChain(null)
            }
        },
    })),
])
