export type dataRetentionBannerLogicType = MakeLogicType<
    dataRetentionBannerLogicValues,
    dataRetentionBannerLogicActions,
    Record<string, any>,
    dataRetentionBannerLogicMeta
>

// Global (per-browser) dismissal + plan-derived eligibility for the events data-retention warning. The per-insight
// "does this query's range exceed retention" check lives in insightRetentionBannerLogic; this one stays a singleton
// so one dismissal covers every insight rather than each insight being dismissed separately.
export const dataRetentionBannerLogic = kea<dataRetentionBannerLogicType>([
    path(['scenes', 'insights', 'dataRetention', 'dataRetentionBannerLogic']),
    connect({
        values: [organizationLogic, ['currentOrganization'], teamLogic, ['currentTeamId']],
    }),
    actions({
        dismiss: true,
    }),
    loaders(({ values }) => ({
        retention: [
            null as EventsRetentionApi | null,
            {
                loadRetentionMonths: async () => {
                    if (values.currentTeamId === null || isSharedView()) {
                        return null
                    }
                    return (await eventsRetentionRetrieve(String(values.currentTeamId))) || null
                },
            },
        ],
    })),
    reducers({
        dismissed: [
            false,
            { persist: true },
            {
                dismiss: () => true,
            },
        ],
    }),
    selectors({
        retentionMonths: [
            (s) => [s.retention],
            (retention: EventsRetentionApi | null): number | null => retention?.retention_months ?? null,
        ],
        nextDeletionLabel: [
            (s) => [s.retention],
            (retention: EventsRetentionApi | null): string | null => planDeletionDateLabel(retention),
        ],
        deletionCutoff: [
            (s) => [s.retention],
            (retention: EventsRetentionApi | null): Dayjs | null =>
                retention?.next_deletion_before ? dayjs.utc(retention.next_deletion_before) : null,
        ],
        // Upgrading doesn't help when someone set a window shorter than the plan's, or when the plan is the longest.
        retentionBannerAction: [
            (s) => [s.retention],
            (retention: EventsRetentionApi | null): RetentionBannerAction | null => {
                if (retention?.retention_months == null) {
                    return null
                }
                if (retention.retention_months < retention.plan_retention_months) {
                    return {
                        children: 'Change retention',
                        to: urls.settings('environment-product-analytics', 'project-events-retention'),
                    }
                }
                return retention.plan_retention_months < LONGEST_PLAN_RETENTION_MONTHS
                    ? { children: 'Upgrade plan', to: urls.organizationBilling() }
                    : null
            },
        ],
        retentionEnforced: [
            (s) => [s.retentionMonths],
            (retentionMonths: number | null): boolean => retentionMonths !== null,
        ],
        retentionPeriodLabel: [
            (s) => [s.retentionMonths],
            (retentionMonths: number | null): string | null =>
                retentionMonths ? retentionMonthsLabel(retentionMonths) : null,
        ],
        accountAgeEligible: [
            (s) => [s.currentOrganization, s.retentionMonths],
            (
                currentOrganization: null | import('~/types').OrganizationType,
                retentionMonths: number | null
            ): boolean => {
                if (!currentOrganization?.created_at || !retentionMonths) {
                    return false
                }
                // Eligible once the account is old enough to have data within 90 days of (or past) its retention
                // horizon — i.e. created before now − retention + 90 days.
                const horizon = dayjs().subtract(retentionMonths, 'month').add(WARN_WITHIN_DAYS, 'day')
                return dayjs(currentOrganization.created_at).isBefore(horizon)
            },
        ],
        retentionApplies: [
            (s) => [s.retentionEnforced, s.accountAgeEligible],
            (retentionEnforced: boolean, accountAgeEligible: boolean): boolean =>
                retentionEnforced && accountAgeEligible,
        ],
        warningEligible: [
            (s) => [s.retentionApplies, s.dismissed],
            (retentionApplies: boolean, dismissed: boolean): boolean => retentionApplies && !dismissed,
        ],
    }),
    listeners(({ actions }) => ({
        [teamLogic.actionTypes.loadCurrentTeamSuccess]: () => {
            actions.loadRetentionMonths()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRetentionMonths()
    }),
])
