import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { type Dayjs, dayjs } from 'lib/dayjs'
import { teamLogic } from 'scenes/teamLogic'

import { isSharedView } from '~/exporter/exporterViewLogic'

import { eventsRetentionRetrieve } from 'products/product_analytics/frontend/generated/api'
import type { EventsRetentionApi } from 'products/product_analytics/frontend/generated/api.schemas'

import { planDeletionDateLabel } from './planDeletionDateLabel'

// Humanize a retention period in months into the attributive form the banners use ("your 7-year retention period"),
// which stays singular and hyphenated because it modifies a noun: whole years read as "N-year", anything else
// as "N-month".
function retentionMonthsLabel(months: number): string {
    if (months % 12 === 0) {
        return `${months / 12}-year`
    }
    return `${months}-month`
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataRetentionBannerLogicValues {
    currentTeamId: number | null // teamLogic
    deletionCutoff: Dayjs | null
    dismissed: boolean
    nextDeletionLabel: string | null
    retention: EventsRetentionApi | null
    retentionLoading: boolean
    retentionPeriodLabel: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataRetentionBannerLogicActions {
    dismiss: () => {
        value: true
    }
    loadRetention: () => any
    loadRetentionFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRetentionSuccess: (
        retention: EventsRetentionApi | null,
        payload?: any
    ) => {
        retention: EventsRetentionApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataRetentionBannerLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        nextDeletionLabel: (retention: EventsRetentionApi | null) => string | null
        deletionCutoff: (retention: EventsRetentionApi | null) => Dayjs | null
        retentionPeriodLabel: (retention: EventsRetentionApi | null) => string | null
    }
}

export type dataRetentionBannerLogicType = MakeLogicType<
    dataRetentionBannerLogicValues,
    dataRetentionBannerLogicActions,
    Record<string, any>,
    dataRetentionBannerLogicMeta
>

// A singleton, so one dismissal covers every insight and dashboard rather than each being dismissed separately.
export const dataRetentionBannerLogic = kea<dataRetentionBannerLogicType>([
    path(['scenes', 'insights', 'dataRetention', 'dataRetentionBannerLogic']),
    connect({
        values: [teamLogic, ['currentTeamId']],
    }),
    actions({
        dismiss: true,
    }),
    loaders(({ values }) => ({
        retention: [
            null as EventsRetentionApi | null,
            {
                loadRetention: async () => {
                    if (values.currentTeamId === null || isSharedView()) {
                        return null
                    }
                    return (await eventsRetentionRetrieve(String(values.currentTeamId))) || null
                },
            },
        ],
    })),
    reducers({
        dismissed: [
            false,
            { persist: true },
            {
                dismiss: () => true,
            },
        ],
    }),
    selectors({
        nextDeletionLabel: [
            (s) => [s.retention],
            (retention: EventsRetentionApi | null): string | null => planDeletionDateLabel(retention),
        ],
        deletionCutoff: [
            (s) => [s.retention],
            (retention: EventsRetentionApi | null): Dayjs | null =>
                retention?.next_deletion_before ? dayjs.utc(retention.next_deletion_before) : null,
        ],
        retentionPeriodLabel: [
            (s) => [s.retention],
            (retention: EventsRetentionApi | null): string | null =>
                retention
                    ? retentionMonthsLabel(
                          Math.min(
                              retention.plan_retention_months,
                              retention.project_retention_months ??
                                  retention.organization_retention_months ??
                                  retention.default_retention_months
                          )
                      )
                    : null,
        ],
    }),
    listeners(({ actions }) => ({
        [teamLogic.actionTypes.loadCurrentTeamSuccess]: () => {
            actions.loadRetention()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRetention()
    }),
])
