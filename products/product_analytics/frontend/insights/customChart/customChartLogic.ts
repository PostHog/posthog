export type CustomChartStatus = 'loading' | 'building' | 'ready' | 'failed' | 'unavailable'

export interface CustomChartLogicProps {
    canvasId: string
}

const POLL_INTERVAL_MS = 5000

export const RETRY_MESSAGE = 'The chart did not build. Find what went wrong, fix it, and publish the chart again.'

export function customChartStatus(
    view: CanvasViewResponseApi | null,
    viewUnavailable: boolean,
    task: CanvasGenerationTask | null
): CustomChartStatus {
    if (viewUnavailable) {
        return 'unavailable'
    }
    if (!view) {
        return 'loading'
    }
    if (view.published_build?.build_status === 'ready' && view.published_build.artifact_url) {
        return 'ready'
    }
    if (view.has_active_build) {
        return 'building'
    }
    if (!view.canvas.generation_task_id) {
        return 'failed'
    }
    const run = task?.latest_run
    return !task || !run || !isTerminalRunStatus(run.status) ? 'building' : 'failed'
}

