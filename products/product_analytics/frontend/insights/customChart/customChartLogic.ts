export type customChartLogicType = MakeLogicType<
    customChartLogicValues,
    customChartLogicActions,
    CustomChartLogicProps,
    customChartLogicMeta
>

export const customChartLogic = kea<customChartLogicType>([
    props({} as CustomChartLogicProps),
    key((props) => props.canvasId),
    path((canvasId) => ['products', 'product_analytics', 'insights', 'customChart', 'customChartLogic', canvasId]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        poll: true,
        openChangeModal: true,
        closeChangeModal: true,
        setChangeMessage: (message: string) => ({ message }),
        refine: (message: string) => ({ message }),
        refineSent: (task: CanvasGenerationTask) => ({ task }),
        refineFailed: true,
        reportRendered: true,
        reportRuntimeError: (message: string) => ({ message }),
    }),
    loaders(({ props, values }) => ({
        view: [
            null as CanvasViewResponseApi | null,
            {
                loadView: async () => canvasesViewRetrieve(String(values.currentProjectId), props.canvasId),
            },
        ],
        task: [
            null as CanvasGenerationTask | null,
            {
                loadTask: async (taskId: string) => loadCanvasGenerationTask(String(values.currentProjectId), taskId),
            },
        ],
    })),
    reducers({
        viewUnavailable: [
            false,
            {
                loadViewFailure: (state, { errorObject }) =>
                    // A failed poll keeps the chart that already loaded.
                    state || [403, 404].includes(errorObject?.status),
                loadViewSuccess: () => false,
            },
        ],
        task: {
            refineSent: (_, { task }) => task,
        },
        changeModalOpen: [
            false,
            { openChangeModal: () => true, closeChangeModal: () => false, refineSent: () => false },
        ],
        changeMessage: ['', { setChangeMessage: (_, { message }) => message, refineSent: () => '' }],
        refining: [
            false,
            {
                refine: () => true,
                refineSent: () => false,
                refineFailed: () => false,
            },
        ],
    }),
    selectors({
        status: [
            (s) => [s.view, s.viewUnavailable, s.task],
            (view, viewUnavailable, task): CustomChartStatus => customChartStatus(view, viewUnavailable, task),
        ],
        liveBuild: [
            (s) => [s.view],
            (view): CanvasBuildApi | null =>
                view?.published_build?.build_status === 'ready' && view.published_build.artifact_url
                    ? view.published_build
                    : null,
        ],
        agentWorking: [
            (s) => [s.view, s.task],
            (view, task): boolean =>
                !!view?.has_active_build || (!!task?.latest_run && !isTerminalRunStatus(task.latest_run.status)),
        ],
        runError: [(s) => [s.task], (task): string | null => task?.latest_run?.error_message ?? null],
    }),
    listeners(({ actions, values, props, cache }) => {
        const syncPolling = (): void => {
            const shouldPoll = values.status === 'building' || values.agentWorking
            if (shouldPoll && !cache.polling) {
                cache.disposables.add(() => {
                    const id = setInterval(() => actions.poll(), POLL_INTERVAL_MS)
                    return () => clearInterval(id)
                }, 'poll')
            } else if (!shouldPoll && cache.polling) {
                cache.disposables.dispose('poll')
            }
            cache.polling = shouldPoll
        }
        return {
            poll: () => {
                actions.loadView()
                const taskId = values.view?.canvas.generation_task_id
                if (taskId) {
                    actions.loadTask(taskId)
                }
            },
            loadViewSuccess: ({ view }) => {
                const taskId = view?.canvas.generation_task_id
                if (taskId && values.task?.id !== taskId && !values.taskLoading) {
                    actions.loadTask(taskId)
                }
                const buildId = values.liveBuild?.id ?? null
                if (buildId && cache.lastBuildId !== undefined && buildId !== cache.lastBuildId) {
                    posthog.capture(CUSTOM_CHART_EVENTS.built, {
                        canvas_id: props.canvasId,
                        is_refinement: cache.lastBuildId !== null,
                    })
                }
                cache.lastBuildId = buildId
                syncPolling()
            },
            loadTaskSuccess: () => {
                if (values.status === 'failed' && !cache.reportedFailed) {
                    cache.reportedFailed = true
                    posthog.capture(CUSTOM_CHART_EVENTS.buildFailed, {
                        canvas_id: props.canvasId,
                        run_status: values.task?.latest_run?.status,
                    })
                }
                syncPolling()
            },
            refine: async ({ message }) => {
                const task = values.task
                const projectId = String(values.currentProjectId)
                if (!task) {
                    actions.refineFailed()
                    return
                }
                try {
                    const run = task.latest_run
                    if (run && !isTerminalRunStatus(run.status)) {
                        await sendCanvasRunMessage(projectId, task.id, run.id, message)
                        actions.refineSent(task)
                    } else {
                        actions.refineSent(
                            await resumeCanvasTask(projectId, task.id, { resumeFromRunId: run?.id ?? null, message })
                        )
                    }
                    cache.reportedFailed = false
                    posthog.capture(CUSTOM_CHART_EVENTS.refined, {
                        canvas_id: props.canvasId,
                        is_retry: message === RETRY_MESSAGE,
                        message_length_chars: message.length,
                    })
                    syncPolling()
                } catch (error) {
                    actions.refineFailed()
                    lemonToast.error(
                        `Couldn't send the change to the agent. ${error instanceof Error ? error.message : 'Try again in a moment.'}`
                    )
                }
            },
            reportRendered: () => {
                if (!cache.reportedRendered) {
                    cache.reportedRendered = true
                    posthog.capture(CUSTOM_CHART_EVENTS.rendered, { canvas_id: props.canvasId })
                }
            },
            reportRuntimeError: ({ message }) => {
                posthog.capture(CUSTOM_CHART_EVENTS.runtimeError, {
                    canvas_id: props.canvasId,
                    message: message.slice(0, 200),
                })
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadView()
    }),
])
