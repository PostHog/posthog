import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { projectLogic } from 'scenes/projectLogic'

import { loadCanvasSpaces } from 'products/canvas/frontend/canvasTasksApi'
import { FREEFORM_TEMPLATE_ID } from 'products/canvas/frontend/canvasTemplates'
import { canvasesCreate, canvasesDestroy } from 'products/canvas/frontend/generated/api'
import { startCanvasGeneration } from 'products/canvas/frontend/startCanvasGeneration'

import { CustomChartData } from './customChartData'
import { CUSTOM_CHART_EVENTS } from './customChartEvents'
import { buildCustomChartInstruction } from './customChartPrompt'

export interface CustomChartModalLogicProps {
    /** One modal per insight view. */
    key: string
    insightName: string
    /** The current results. The agent builds the chart against their shape. */
    data: CustomChartData | null
    onCreated: (canvasId: string) => void
}

const MAX_CANVAS_NAME_LENGTH = 400

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customChartModalLogicValues {
    currentProjectId: number | null // projectLogic
    description: string
    fromSuggestion: boolean
    isOpen: boolean
    submitDisabledReason: string | null
    submitting: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customChartModalLogicActions {
    closeModal: () => {
        value: true
    }
    openModal: () => {
        value: true
    }
    setDescription: (
        description: string,
        fromSuggestion?: boolean
    ) => {
        description: string
        fromSuggestion: boolean
    }
    submit: () => {
        value: true
    }
    submitFailed: () => {
        value: true
    }
    submitSucceeded: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customChartModalLogicMeta {
    key: any
    __keaTypeGenInternalSelectorTypes: {
        submitDisabledReason: (description: any, data: any) => string | null
    }
}

export type customChartModalLogicType = MakeLogicType<
    customChartModalLogicValues,
    customChartModalLogicActions,
    CustomChartModalLogicProps,
    customChartModalLogicMeta
>

export const customChartModalLogic = kea<customChartModalLogicType>([
    props({} as CustomChartModalLogicProps),
    key((props) => props.key),
    path((key) => ['products', 'product_analytics', 'insights', 'customChart', 'customChartModalLogic', key]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        openModal: true,
        closeModal: true,
        setDescription: (description: string, fromSuggestion: boolean = false) => ({ description, fromSuggestion }),
        submit: true,
        submitSucceeded: true,
        submitFailed: true,
    }),
    reducers({
        isOpen: [false, { openModal: () => true, closeModal: () => false, submitSucceeded: () => false }],
        description: [
            '',
            {
                setDescription: (_, { description }) => description,
                submitSucceeded: () => '',
            },
        ],
        fromSuggestion: [
            false,
            {
                setDescription: (_, { fromSuggestion }) => fromSuggestion,
                submitSucceeded: () => false,
            },
        ],
        submitting: [false, { submit: () => true, submitSucceeded: () => false, submitFailed: () => false }],
    }),
    selectors({
        submitDisabledReason: [
            (s, p) => [s.description, p.data],
            (description, data): string | null => {
                if (!data) {
                    return 'Wait for the insight to load its results'
                }
                return description.trim() ? null : 'Describe the chart first'
            },
        ],
    }),
    listeners(({ actions, values, props }) => ({
        submit: async () => {
            const data = props.data
            const projectId = values.currentProjectId ? String(values.currentProjectId) : null
            if (!data || !projectId || values.submitDisabledReason) {
                actions.submitFailed()
                return
            }
            let canvasId: string | null = null
            try {
                const spaces = await loadCanvasSpaces(projectId)
                // The project's general space lets everyone who can see the insight see its chart.
                const space =
                    spaces.find((candidate) => candidate.system_role === 'general') ??
                    spaces.find((candidate) => candidate.system_role === 'personal')
                if (!space) {
                    throw new Error('No space is available for the chart.')
                }
                const insightName = props.insightName.trim() || 'Untitled insight'
                const canvas = await canvasesCreate(projectId, {
                    channel_id: space.id,
                    name: `Custom chart: ${insightName}`.slice(0, MAX_CANVAS_NAME_LENGTH),
                    template_id: FREEFORM_TEMPLATE_ID,
                    description: values.description.trim(),
                })
                canvasId = canvas.id
                await startCanvasGeneration({
                    projectId,
                    canvas,
                    spaceName: space.name,
                    instruction: buildCustomChartInstruction({
                        description: values.description,
                        insightName,
                        data,
                    }),
                    fromSuggestion: values.fromSuggestion,
                    surface: 'web_insight_custom_chart',
                })
                posthog.capture(CUSTOM_CHART_EVENTS.created, {
                    canvas_id: canvas.id,
                    query_kind: data.query.kind,
                    from_suggestion: values.fromSuggestion,
                    description_length_chars: values.description.trim().length,
                    space_role: space.system_role,
                })
                props.onCreated(canvas.id)
                actions.submitSucceeded()
            } catch (error) {
                if (canvasId) {
                    await canvasesDestroy(projectId, canvasId).catch(() => undefined)
                }
                lemonToast.error(
                    `Couldn't start the custom chart. ${error instanceof Error ? error.message : 'Try again in a moment.'}`
                )
                actions.submitFailed()
            }
        },
    })),
])
