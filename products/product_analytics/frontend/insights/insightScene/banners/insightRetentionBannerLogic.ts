export const insightRetentionBannerLogic = kea<insightRetentionBannerLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['scenes', 'insights', 'dataRetention', 'insightRetentionBannerLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            dataRetentionBannerLogic,
            ['deletionCutoff', 'dismissed'],
            insightDataLogic(props),
            ['insightData', 'query'],
        ],
    })),
    selectors({
        shouldShowBanner: [
            (s) => [s.dismissed, s.deletionCutoff, s.query, s.insightData],
            (
                dismissed: boolean,
                deletionCutoff: Dayjs | null,
                query: Node | null,
                insightData: Record<string, any>
            ): boolean =>
                !dismissed &&
                !shadesRetentionDeletion(query) &&
                rangeReachesBefore({
                    query,
                    resolvedDateFrom: insightData?.resolved_date_range?.date_from,
                    cutoff: deletionCutoff,
                }),
        ],
    }),
])
