export type homeTabDefaultLogicType = MakeLogicType<
    homeTabDefaultLogicValues,
    homeTabDefaultLogicActions,
    Record<string, any>,
    homeTabDefaultLogicMeta
>

export const homeTabDefaultLogic = kea<homeTabDefaultLogicType>([
    path(['scenes', 'saved-insights', 'homeTabDefaultLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),
    actions({
        setDates: (dateFrom: string | null, dateTo: string | null, explicitDate?: boolean) => ({
            dateFrom,
            dateTo,
            explicitDate,
        }),
        setCompare: (compare: boolean) => ({ compare }),
        setSelectedContentKey: (key: HomeTabContentKey) => ({ key }),
        setSelectedMetric: (key: HomeTabMetricKey) => ({ key }),
        setSelectedView: (view: HomeTabViewKey) => ({ view }),
        setSelectedViewMetric: (view: HomeTabViewKey, key: string) => ({ view, key }),
    }),
    reducers({
        dateRange: [
            HOME_TAB_DEFAULT_DATE_RANGE,
            {
                setDates: (_, { dateFrom, dateTo, explicitDate }) => ({
                    date_from: dateFrom ?? HOME_TAB_DEFAULT_DATE_RANGE.date_from,
                    date_to: dateTo,
                    explicitDate,
                }),
            },
        ],
        compare: [true, { setCompare: (_, { compare }) => compare }],
        selectedContentKey: ['top_pages' as HomeTabContentKey, { setSelectedContentKey: (_, { key }) => key }],
        selectedMetric: ['active_users' as HomeTabMetricKey, { setSelectedMetric: (_, { key }) => key }],
        selectedView: ['overview' as HomeTabViewKey, { setSelectedView: (_, { view }) => view }],
        selectedViewMetrics: [
            {} as Partial<Record<HomeTabViewKey, string>>,
            { setSelectedViewMetric: (state, { view, key }) => ({ ...state, [view]: key }) },
        ],
    }),
    selectors({
        showViews: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.PRODUCT_ANALYTICS_HOME_VIEWS],
        ],
    }),
    listeners(() => ({
        setSelectedView: ({ view }) => {
            // pinned: analytics event name, renaming breaks the Home views adoption insights
            posthog.capture('product analytics home view changed', { view })
        },
    })),
])
