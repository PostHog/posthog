import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { dayjs } from 'lib/dayjs'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import type { HealthIssuesResponse } from 'scenes/health/healthSceneLogic'
import type { HealthIssue } from 'scenes/health/types'
import { autoRunMaxPrompt } from 'scenes/max/maxPrompt'
import { teamLogic } from 'scenes/teamLogic'

import { sidePanelStateLogic } from '~/layout/navigation-3000/sidepanel/sidePanelStateLogic'
import { SidePanelTab } from '~/types'

import { stoppedEventPayload, stoppedEventPrompt } from './stoppedEventText'

// Kept in sync with EVENT_STOPPED_KIND in products/product_analytics/backend/temporal/health_checks/event_stopped.py.
export const EVENT_STOPPED_KIND = 'event_stopped'

export type StoppedEventAction = 'posthog_ai' | 'view_event' | 'review_insights' | 'dismiss' | 'snooze'

