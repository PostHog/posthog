export type stoppedEventsLogicType = MakeLogicType<
    stoppedEventsLogicValues,
    stoppedEventsLogicActions,
    Record<string, any>,
    stoppedEventsLogicMeta
>

export const stoppedEventsLogic = kea<stoppedEventsLogicType>([
    path(['products', 'product_analytics', 'insights', 'home', 'stoppedEvents', 'stoppedEventsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], sidePanelStateLogic, ['sidePanelOpen', 'selectedTab']],
        actions: [sidePanelStateLogic, ['openSidePanel']],
    })),
    actions({
        dismissIssue: (issue: HealthIssue) => ({ issue }),
        snoozeIssue: (issue: HealthIssue) => ({ issue }),
        investigateWithPostHogAI: (issue: HealthIssue) => ({ issue }),
        reportNoticeViewed: true,
        reportActionClicked: (action: StoppedEventAction, issue: HealthIssue) => ({ action, issue }),
    }),
    loaders(({ values }) => ({
        issues: [
            null as HealthIssue[] | null,
            {
                loadIssues: async () => {
                    const response = await api.get<HealthIssuesResponse>(
                        `api/projects/${values.currentTeamIdStrict}/health_issues/?kind=${EVENT_STOPPED_KIND}&status=active&dismissed=false`
                    )
                    return response.results
                },
                removeIssue: ({ id }: { id: string }) => (values.issues ?? []).filter((issue) => issue.id !== id),
            },
        ],
    })),
    selectors({
        visibleIssues: [
            (s) => [s.issues],
            (issues: HealthIssue[] | null): HealthIssue[] | null =>
                issues?.filter((issue) => !issue.snoozed_until || dayjs(issue.snoozed_until).isBefore(dayjs())) ?? null,
        ],
        postHogAIOpen: [
            (s) => [s.sidePanelOpen, s.selectedTab],
            (sidePanelOpen: boolean, selectedTab: SidePanelTab | null): boolean =>
                sidePanelOpen && selectedTab === SidePanelTab.Max,
        ],
    }),
    listeners(({ actions, values }) => ({
        loadIssuesSuccess: () => {
            if (values.visibleIssues?.length) {
                actions.reportNoticeViewed()
            }
        },
        dismissIssue: async ({ issue }) => {
            actions.reportActionClicked('dismiss', issue)
            try {
                await api.update(`api/projects/${values.currentTeamIdStrict}/health_issues/${issue.id}/`, {
                    dismissed: true,
                })
                actions.removeIssue({ id: issue.id })
            } catch {
                lemonToast.error("Couldn't dismiss this event. Try again in a moment.")
            }
        },
        snoozeIssue: async ({ issue }) => {
            actions.reportActionClicked('snooze', issue)
            try {
                await api.update(`api/projects/${values.currentTeamIdStrict}/health_issues/${issue.id}/`, {
                    snoozed_until: '7d',
                })
                actions.removeIssue({ id: issue.id })
            } catch {
                lemonToast.error("Couldn't snooze this event. Try again in a moment.")
            }
        },
        investigateWithPostHogAI: ({ issue }) => {
            // A second request while PostHog AI is open would start another run for the same event.
            if (values.postHogAIOpen) {
                return
            }
            actions.reportActionClicked('posthog_ai', issue)
            actions.openSidePanel(SidePanelTab.Max, autoRunMaxPrompt(stoppedEventPrompt(stoppedEventPayload(issue))))
        },
        reportNoticeViewed: () => {
            // pinned: analytics event name, renaming breaks the activation funnel
            posthog.capture('stopped events notice viewed', {
                event_count: values.visibleIssues?.length ?? 0,
                with_annotation_count: values.visibleIssues?.filter((issue) => !!issue.payload.annotation).length ?? 0,
            })
        },
        reportActionClicked: ({ action, issue }) => {
            // pinned: analytics event name, renaming breaks the activation funnel
            posthog.capture('stopped event action clicked', {
                action,
                insight_count: issue.payload.insight_count,
                has_annotation: !!issue.payload.annotation,
                issue_age_days: dayjs().diff(dayjs(issue.created_at), 'day'),
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadIssues()
    }),
])
