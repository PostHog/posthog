import { MakeLogicType, connect, kea, key, listeners, path, props, selectors } from 'kea'

import { DashboardLogicProps, dashboardLogic } from 'scenes/dashboard/dashboardLogic'
import { teamLogic } from 'scenes/teamLogic'

import { DashboardPlacement, DashboardTile, DashboardType } from '~/types'

/** `embedded` shows a read-only dashboard inside another view. `page` shows the full, editable dashboard. */
export type HomeTabDashboardDisplay = 'embedded' | 'page'

export interface HomeTabDashboardLogicProps {
    dashboardId: number
    display: HomeTabDashboardDisplay
}

export const homeTabDashboardProps = (
    dashboardId: number,
    display: HomeTabDashboardDisplay = 'embedded'
): DashboardLogicProps =>
    display === 'page'
        ? { id: dashboardId, placement: DashboardPlacement.Dashboard }
        : { id: dashboardId, placement: DashboardPlacement.Builtin, readOnly: true }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface homeTabDashboardLogicValues {
    canEditDashboard: boolean // dashboardLogic
    dashboard: DashboardType | null // dashboardLogic
    dashboardFailedToLoad: boolean // dashboardLogic
    error404: boolean // dashboardLogic
    tiles: DashboardTile[] // dashboardLogic
    dashboardEmpty: boolean
    dashboardMissing: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface homeTabDashboardLogicActions {
    dashboardNotFound: () => {
        value: true
    } // dashboardLogic
    loadDashboard: (payload: { action: import('scenes/dashboard/dashboardLogic').DashboardLoadAction }) => {
        action: import('scenes/dashboard/dashboardLogic').DashboardLoadAction
    } // dashboardLogic
    loadCurrentTeam: () => any // teamLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface homeTabDashboardLogicMeta {
    key: number
    __keaTypeGenInternalSelectorTypes: {
        dashboardEmpty: (
            dashboard: DashboardType | null,
            tiles: DashboardTile[],
            dashboardFailedToLoad: boolean
        ) => boolean
        dashboardMissing: (error404: boolean, dashboard: DashboardType | null) => boolean
    }
}

export type homeTabDashboardLogicType = MakeLogicType<
    homeTabDashboardLogicValues,
    homeTabDashboardLogicActions,
    HomeTabDashboardLogicProps,
    homeTabDashboardLogicMeta
>

export const homeTabDashboardLogic = kea<homeTabDashboardLogicType>([
    props({} as HomeTabDashboardLogicProps),
    key((props) => props.dashboardId),
    path((key) => ['products', 'product_analytics', 'home', 'homeTabDashboardLogic', key]),
    connect((props: HomeTabDashboardLogicProps) => ({
        values: [
            dashboardLogic(homeTabDashboardProps(props.dashboardId, props.display)),
            ['dashboard', 'error404', 'tiles', 'dashboardFailedToLoad', 'canEditDashboard'],
        ],
        actions: [
            dashboardLogic(homeTabDashboardProps(props.dashboardId, props.display)),
            ['dashboardNotFound', 'loadDashboard'],
            teamLogic,
            ['loadCurrentTeam'],
        ],
    })),
    selectors({
        // A failed reload keeps the old tiles, so the dashboard's own error and retry show instead.
        dashboardEmpty: [
            (s) => [s.dashboard, s.tiles, s.dashboardFailedToLoad],
            (dashboard: DashboardType | null, tiles: DashboardTile[], dashboardFailedToLoad: boolean): boolean =>
                !!dashboard && tiles.length === 0 && !dashboardFailedToLoad,
        ],
        dashboardMissing: [
            (s) => [s.error404, s.dashboard],
            (error404: boolean, dashboard: DashboardType | null): boolean => error404 && !dashboard,
        ],
    }),
    listeners(({ actions }) => ({
        // Another tab or person can delete the dashboard after this team loaded. The backend clears
        // the Home dashboard on delete, so a reload returns the team to PostHog Home.
        dashboardNotFound: () => {
            actions.loadCurrentTeam()
        },
    })),
])
