export type homeTabLoadTimeLogicType = MakeLogicType<
    homeTabLoadTimeLogicValues,
    homeTabLoadTimeLogicActions,
    HomeTabLoadTimeLogicProps,
    homeTabLoadTimeLogicMeta
>

export const homeTabLoadTimeLogic: LogicWrapper<homeTabLoadTimeLogicType> = kea<homeTabLoadTimeLogicType>([
    props({} as HomeTabLoadTimeLogicProps),
    key(({ teamId }) => teamId ?? 'none'),
    path((key) => ['products', 'product_analytics', 'home', 'homeTabLoadTimeLogic', key]),
    connect(({ teamId }: HomeTabLoadTimeLogicProps) => ({
        values: [dataNodeCollectionLogic({ key: homeTabDataCollectionId(teamId) }), ['collectionNodeStatus']],
        actions: [
            dataNodeCollectionLogic({ key: homeTabDataCollectionId(teamId) }),
            [
                'collectionNodeLoadData',
                'collectionNodeLoadDataSuccess',
                'collectionNodeLoadDataFailure',
                'visibilityChanged',
                'pageHidden',
                'startPageVisit',
                'endPageVisit',
            ],
        ],
    })),
    actions({
        checkLoaded: true,
    }),
    listeners(({ actions, values, props, cache }) => {
        const reportLoad = (status: 'success' | 'failure' | 'cancelled', options?: CaptureOptions): void => {
            if (cache.hasReported) {
                return
            }
            cache.hasReported = true
            posthog.capture(
                'product_analytics_home_load',
                {
                    team_id: props.teamId,
                    visit_id: cache.visitId,
                    duration_ms: Math.round(performance.now() - cache.mountStart),
                    status,
                    load_type: cache.hasObservedLoading ? 'query' : 'cached',
                    tile_count: props.tileIds.length,
                    failed_tile_count: props.tileIds.filter((id) => values.collectionNodeStatus[id]?.hasError).length,
                    was_hidden: cache.wasHidden,
                    default_date_range: props.defaultDateRange,
                    compare: props.compare,
                },
                options
            )
        }
        cache.reportLoad = reportLoad
        return {
            collectionNodeLoadData: ({ id }) => {
                if (props.tileIds.includes(id)) {
                    cache.hasObservedLoading = true
                }
            },
            collectionNodeLoadDataSuccess: () => actions.checkLoaded(),
            collectionNodeLoadDataFailure: () => actions.checkLoaded(),
            visibilityChanged: ({ hidden }) => {
                cache.wasHidden ||= hidden
            },
            pageHidden: () => reportLoad('cancelled', { transport: 'sendBeacon' }),
            checkLoaded: async (_, breakpoint) => {
                await breakpoint(0)
                if (cache.hasReported || !props.tileIds.length) {
                    return
                }
                const statuses = props.tileIds.map((id) => values.collectionNodeStatus[id])
                cache.hasObservedLoading ||= statuses.some((status) => status?.isLoading)
                if (statuses.every((status) => status && !status.isLoading)) {
                    reportLoad(statuses.some((status) => status?.hasError) ? 'failure' : 'success')
                }
            },
        }
    }),
    afterMount(({ actions, values, props, cache }) => {
        cache.mountStart = performance.now()
        cache.visitId = uuid()
        cache.hasReported = false
        cache.hasObservedLoading = props.tileIds.some((id) => values.collectionNodeStatus[id]?.isLoading)
        cache.wasHidden = document.visibilityState === 'hidden'
        actions.startPageVisit(cache.visitId)
        posthog.capture('product_analytics_home_mounted', { team_id: props.teamId, visit_id: cache.visitId })
        actions.checkLoaded()
    }),
    propsChanged(({ actions }) => actions.checkLoaded()),
    beforeUnmount(({ actions, cache }) => {
        cache.reportLoad('cancelled')
        actions.endPageVisit()
    }),
])
