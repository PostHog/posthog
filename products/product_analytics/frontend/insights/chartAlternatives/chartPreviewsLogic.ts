export const chartPreviewsLogic = kea<chartPreviewsLogicType>([
    props({} as ChartAlternativesLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'chartAlternatives', 'chartPreviewsLogic', key]),
    connect((props: ChartAlternativesLogicProps) => ({
        values: [
            chartAlternativesLogic(props),
            ['alternatives', 'currentDisplay', 'galleryOpen', 'options', 'trendsSource'],
            insightVizDataLogic(props),
            ['insightData', 'insightDataLoading'],
        ],
        actions: [
            chartAlternativesLogic(props),
            ['toggleGallery'],
            insightVizDataLogic(props),
            ['loadDataSuccess', 'setInsightData'],
        ],
    })),
    actions({
        rememberTimeSeries: (entry: TimeSeriesEntry) => ({ entry }),
    }),
    reducers({
        rememberedTimeSeries: [
            null as TimeSeriesEntry | null,
            {
                rememberTimeSeries: (_, { entry }) => entry,
            },
        ],
    }),
    selectors({
        freeResponse: [
            (s) => [s.insightData],
            (insightData: Record<string, any> | null): AnyResponseType | null =>
                insightData?.result != null || insightData?.results != null ? (insightData as AnyResponseType) : null,
        ],
        timeSeriesKey: [
            (s) => [s.trendsSource],
            (trendsSource: TrendsQuery | null): string | null =>
                trendsSource
                    ? JSON.stringify(applyChartDisplay(trendsSource, ChartDisplayType.ActionsLineGraph))
                    : null,
        ],
        loadedTimeSeries: [
            (s) => [s.timeSeriesKey, s.currentDisplay, s.freeResponse],
            (
                timeSeriesKey: string | null,
                currentDisplay: ChartDisplayType,
                freeResponse: AnyResponseType | null
            ): TimeSeriesEntry | null =>
                timeSeriesKey &&
                freeResponse &&
                RAW_TIME_SERIES_DISPLAYS.has(currentDisplay) &&
                hasResults(freeResponse)
                    ? { key: timeSeriesKey, response: freeResponse }
                    : null,
        ],
        // A total value result has no buckets, so time series tiles reuse the last time series loaded for this query.
        timeSeriesResponse: [
            (s) => [s.timeSeriesKey, s.rememberedTimeSeries],
            (timeSeriesKey: string | null, rememberedTimeSeries: TimeSeriesEntry | null): AnyResponseType | null =>
                timeSeriesKey && rememberedTimeSeries?.key === timeSeriesKey ? rememberedTimeSeries.response : null,
        ],
        previews: [
            (s) => [
                s.trendsSource,
                s.options,
                s.alternatives,
                s.freeResponse,
                s.timeSeriesResponse,
                s.insightDataLoading,
                (_, props) => keyForInsightLogicProps('new')(props),
            ],
            (
                trendsSource: TrendsQuery | null,
                options: ChartDisplayOptionGroup[],
                alternatives: ChartDisplayOption[],
                freeResponse: AnyResponseType | null,
                timeSeriesResponse: AnyResponseType | null,
                insightDataLoading: boolean,
                logicKey: string
            ): ChartPreview[] => {
                if (!trendsSource) {
                    return []
                }
                const suggestedDisplays = new Set(alternatives.map((option) => option.display))
                const remaining = options.flatMap((group) =>
                    group.options.filter((option) => !suggestedDisplays.has(option.display))
                )
                const ordered = [
                    ...alternatives,
                    ...remaining.filter((option) => !option.disabledReason),
                    ...remaining.filter((option) => !!option.disabledReason),
                ]
                return ordered.map((option) => {
                    const derived =
                        option.disabledReason || !freeResponse || insightDataLoading
                            ? null
                            : deriveChartPreview(option.display, trendsSource, freeResponse, timeSeriesResponse)
                    return {
                        option,
                        suggested: suggestedDisplays.has(option.display),
                        query: previewVizNode(trendsSource, option.display),
                        response: derived?.response ?? null,
                        sample: derived?.sample ?? false,
                        uniqueKey: `chart-preview-${logicKey}-${option.display}`,
                    }
                })
            },
        ],
    }),
    listeners(({ actions, values }) => {
        const rememberLoadedTimeSeries = (): void => {
            if (values.loadedTimeSeries) {
                actions.rememberTimeSeries(values.loadedTimeSeries)
            }
        }
        return {
            toggleGallery: () => {
                if (!values.galleryOpen || values.insightDataLoading) {
                    return
                }
                const eligiblePreviews = values.previews.filter((preview) => !preview.option.disabledReason)
                const loadedPreviews = eligiblePreviews.filter((preview) => preview.response !== null)
                const samplePreviews = loadedPreviews.filter((preview) => preview.sample)
                posthog.capture('insight chart alternatives viewed', {
                    current_display: values.currentDisplay,
                    eligible_chart_count: eligiblePreviews.length,
                    eligible_displays: eligiblePreviews.map((preview) => preview.option.display),
                    preview_count: loadedPreviews.length,
                    preview_displays: loadedPreviews.map((preview) => preview.option.display),
                    sample_preview_count: samplePreviews.length,
                    sample_preview_displays: samplePreviews.map((preview) => preview.option.display),
                    suggested_displays: eligiblePreviews
                        .filter((preview) => preview.suggested)
                        .map((preview) => preview.option.display),
                    all_previews_loaded:
                        eligiblePreviews.length > 0 && loadedPreviews.length === eligiblePreviews.length,
                })
            },
            loadDataSuccess: rememberLoadedTimeSeries,
            setInsightData: rememberLoadedTimeSeries,
        }
    }),
    // The insight can finish loading before this logic mounts.
    afterMount(({ actions, values }) => {
        if (values.loadedTimeSeries) {
            actions.rememberTimeSeries(values.loadedTimeSeries)
        }
    }),
])
