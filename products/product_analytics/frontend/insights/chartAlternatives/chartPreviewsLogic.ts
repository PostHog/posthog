export const chartPreviewsLogic = kea<chartPreviewsLogicType>([
    props({} as ChartAlternativesLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'chartAlternatives', 'chartPreviewsLogic', key]),
    connect((props: ChartAlternativesLogicProps) => ({
        values: [
            chartAlternativesLogic(props),
            ['alternatives', 'currentDisplay', 'galleryOpen', 'options', 'trendsSource'],
            insightVizDataLogic(props),
            ['insightData', 'insightDataLoading'],
        ],
        actions: [
            chartAlternativesLogic(props),
            ['openGallery', 'toggleGallery'],
            insightVizDataLogic(props),
            ['loadDataSuccess', 'setInsightData'],
        ],
    })),
    actions({
        loadCachedTimeSeries: (key: string, responseVersion: number) => ({ key, responseVersion }),
        rememberTimeSeries: (entry: TimeSeriesEntry) => ({ entry }),
        markTimeSeriesMiss: (key: string, responseVersion: number) => ({ key, responseVersion }),
        tryLoadCachedTimeSeries: true,
    }),
    loaders(({ values }) => ({
        cachedTimeSeries: [
            null as TimeSeriesEntry | null,
            {
                loadCachedTimeSeries: async ({ key }, breakpoint) => {
                    const source = values.timeSeriesSource
                    if (values.timeSeriesKey !== key || !source) {
                        return null
                    }
                    const response = await performQuery(source, undefined, 'force_cache').catch(() => null)
                    breakpoint()
                    return response && hasResults(response) ? { key, response } : null
                },
            },
        ],
    })),
    reducers({
        rememberedTimeSeries: [
            null as TimeSeriesEntry | null,
            {
                rememberTimeSeries: (state: TimeSeriesEntry | null, { entry }) =>
                    state?.key === entry.key && state.response === entry.response ? state : entry,
            },
        ],
        responseVersion: [
            0,
            {
                loadDataSuccess: (state) => state + 1,
                setInsightData: (state) => state + 1,
            },
        ],
        cacheRequest: [
            null as CacheRequest | null,
            {
                loadCachedTimeSeries: (_, { key, responseVersion }) => ({ key, responseVersion }),
                loadCachedTimeSeriesSuccess: (state, { payload }) =>
                    state && payload && state.key === payload.key && state.responseVersion === payload.responseVersion
                        ? null
                        : state,
            },
        ],
        timeSeriesMiss: [
            null as CacheRequest | null,
            {
                markTimeSeriesMiss: (_, { key, responseVersion }) => ({ key, responseVersion }),
            },
        ],
    }),
    selectors({
        freeResponse: [
            (s) => [s.insightData],
            (insightData: Record<string, any> | null): AnyResponseType | null =>
                insightData?.result != null || insightData?.results != null ? (insightData as AnyResponseType) : null,
        ],
        timeSeriesSource: [
            (s) => [s.trendsSource],
            (trendsSource: TrendsQuery | null): TrendsQuery | null =>
                trendsSource ? applyChartDisplay(trendsSource, ChartDisplayType.ActionsLineGraph) : null,
        ],
        timeSeriesKey: [
            (s) => [s.timeSeriesSource],
            (timeSeriesSource: TrendsQuery | null): string | null =>
                timeSeriesSource ? JSON.stringify(timeSeriesSource) : null,
        ],
        timeSeriesResponse: [
            (s) => [s.timeSeriesKey, s.currentDisplay, s.freeResponse, s.rememberedTimeSeries],
            (
                timeSeriesKey: string | null,
                currentDisplay: ChartDisplayType,
                freeResponse: AnyResponseType | null,
                rememberedTimeSeries: TimeSeriesEntry | null
            ): AnyResponseType | null => {
                if (freeResponse && RAW_TIME_SERIES_DISPLAYS.has(currentDisplay)) {
                    return freeResponse
                }
                return timeSeriesKey &&
                    rememberedTimeSeries?.key === timeSeriesKey &&
                    isAtLeastAsFresh(rememberedTimeSeries.response, freeResponse)
                    ? rememberedTimeSeries.response
                    : null
            },
        ],
        previews: [
            (s) => [
                s.trendsSource,
                s.options,
                s.alternatives,
                s.freeResponse,
                s.timeSeriesResponse,
                s.insightDataLoading,
                s.cachedTimeSeriesLoading,
                (_, props) => keyForInsightLogicProps('new')(props),
            ],
            (
                trendsSource: TrendsQuery | null,
                options: ChartDisplayOptionGroup[],
                alternatives: ChartDisplayOption[],
                freeResponse: AnyResponseType | null,
                timeSeriesResponse: AnyResponseType | null,
                insightDataLoading: boolean,
                cachedTimeSeriesLoading: boolean,
                logicKey: string
            ): ChartPreview[] => {
                if (!trendsSource) {
                    return []
                }
                const suggestedDisplays = new Set(alternatives.map((option) => option.display))
                const remaining = options.flatMap((group) =>
                    group.options.filter((option) => !suggestedDisplays.has(option.display))
                )
                const ordered = [
                    ...alternatives,
                    ...remaining.filter((option) => !option.disabledReason),
                    ...remaining.filter((option) => !!option.disabledReason),
                ]
                return ordered.map((option) => {
                    const derived =
                        option.disabledReason || !freeResponse || insightDataLoading
                            ? null
                            : deriveChartPreview(option.display, trendsSource, freeResponse, timeSeriesResponse)
                    return {
                        option,
                        suggested: suggestedDisplays.has(option.display),
                        loading: !option.disabledReason && !derived && (insightDataLoading || cachedTimeSeriesLoading),
                        query: previewVizNode(trendsSource, option.display),
                        response: derived?.response ?? null,
                        sample: derived?.sample ?? false,
                        uniqueKey: `chart-preview-${logicKey}-${option.display}`,
                    }
                })
            },
        ],
    }),
    listeners(({ actions, values }) => {
        const rememberLoadedTimeSeries = (response: AnyResponseType | null | undefined): void => {
            if (
                response &&
                values.timeSeriesKey &&
                RAW_TIME_SERIES_DISPLAYS.has(values.currentDisplay) &&
                hasResults(response)
            ) {
                actions.rememberTimeSeries({ key: values.timeSeriesKey, response })
            }
        }
        const loadCachedTimeSeries = (): void => {
            const {
                cacheRequest,
                freeResponse,
                galleryOpen,
                responseVersion,
                timeSeriesKey,
                timeSeriesMiss,
                timeSeriesResponse,
            } = values
            if (
                galleryOpen &&
                timeSeriesKey &&
                freeResponse &&
                !values.insightDataLoading &&
                !timeSeriesResponse &&
                (timeSeriesMiss?.key !== timeSeriesKey || timeSeriesMiss.responseVersion !== responseVersion) &&
                (cacheRequest?.key !== timeSeriesKey || cacheRequest.responseVersion !== responseVersion)
            ) {
                actions.loadCachedTimeSeries(timeSeriesKey, responseVersion)
            }
        }
        return {
            loadDataSuccess: ({ response }) => {
                rememberLoadedTimeSeries(response)
                actions.tryLoadCachedTimeSeries()
            },
            setInsightData: (response) => {
                rememberLoadedTimeSeries(response)
                actions.tryLoadCachedTimeSeries()
            },
            openGallery: () => {
                rememberLoadedTimeSeries(values.freeResponse)
                actions.tryLoadCachedTimeSeries()
            },
            toggleGallery: () => {
                if (values.galleryOpen) {
                    rememberLoadedTimeSeries(values.freeResponse)
                    actions.tryLoadCachedTimeSeries()
                }
            },
            tryLoadCachedTimeSeries: async (_, breakpoint) => {
                await breakpoint(0)
                loadCachedTimeSeries()
            },
            loadCachedTimeSeriesSuccess: ({ cachedTimeSeries, payload }) => {
                if (!payload) {
                    return
                }
                if (payload.key !== values.timeSeriesKey || payload.responseVersion !== values.responseVersion) {
                    return
                }
                if (cachedTimeSeries && isAtLeastAsFresh(cachedTimeSeries.response, values.freeResponse)) {
                    actions.rememberTimeSeries(cachedTimeSeries)
                } else {
                    actions.markTimeSeriesMiss(payload.key, payload.responseVersion)
                }
            },
        }
    }),
])
