export function previewVizNode(querySource: TrendsQuery, display: ChartDisplayType): InsightVizNode {
    return {
        kind: NodeKind.InsightVizNode,
        source: applyChartDisplay(querySource, display),
        embedded: true,
        hidePersonsModal: true,
        showHeader: false,
        showTable: false,
        showLastComputation: false,
        showLastComputationRefresh: false,
    }
}

function hasResults(response: AnyResponseType | null | undefined): boolean {
    const queryResponse = response as { result?: unknown; results?: unknown } | null | undefined
    const raw = queryResponse?.results ?? queryResponse?.result
    return Array.isArray(raw) && raw.length > 0
}

function isAtLeastAsFresh(response: AnyResponseType, currentResponse: AnyResponseType | null): boolean {
    const currentLastRefresh = (currentResponse as { last_refresh?: string | null } | null)?.last_refresh
    if (!currentLastRefresh) {
        return true
    }
    const lastRefresh = (response as { last_refresh?: string | null }).last_refresh
    return !!lastRefresh && Date.parse(lastRefresh) >= Date.parse(currentLastRefresh)
}

