type ChartAlternativeQuerySource = chartAlternativesLogicValues['querySource']

const optionForDisplay = (
    options: ChartDisplayOptionGroup[],
    display: ChartDisplayType
): ChartDisplayOption | undefined =>
    options.flatMap((group) => group.options).find((option) => option.display === display)

export const chartAlternativesLogic = kea<chartAlternativesLogicType>([
    props({} as ChartAlternativesLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'chartAlternatives', 'chartAlternativesLogic', key]),
    connect((props: ChartAlternativesLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            insightLogic(props),
            ['canEditInsight', 'editingDisabledReason', 'insightId', 'isInDashboardContext'],
            insightVizDataLogic(props),
            ['display', 'insightDataLoading', 'isSingleSeriesOutput', 'isTrends', 'query', 'querySource', 'series'],
        ],
        actions: [
            insightLogic(props),
            ['saveInsightSuccess'],
            insightDataLogic(props),
            ['setQuery'],
            insightVizDataLogic(props),
            ['updateQuerySource'],
        ],
    })),
    actions({
        openGallery: true,
        closeGallery: true,
        selectChart: (display: ChartDisplayType, source: ChartAlternativeSource) => ({ display, source }),
        requestSelection: (selection: ChartAlternativeSelection) => ({ selection }),
        clearPendingSelection: true,
        confirmSelection: true,
        recordSelection: (originalQuery: Node, lastAppliedQuery: Node, source: ChartAlternativeSource) => ({
            originalQuery,
            lastAppliedQuery,
            source,
        }),
        invalidateReturn: true,
        returnToOriginal: true,
    }),
    reducers({
        galleryOpen: [false, { openGallery: () => true, closeGallery: () => false, requestSelection: () => false }],
        pendingSelection: [
            null as ChartAlternativeSelection | null,
            {
                requestSelection: (_, { selection }) => selection,
                clearPendingSelection: () => null,
                invalidateReturn: () => null,
            },
        ],
        originalQuery: [
            null as Node | null,
            {
                recordSelection: (state, { originalQuery }) => state ?? originalQuery,
                invalidateReturn: () => null,
            },
        ],
        lastAppliedQuery: [
            null as Node | null,
            {
                recordSelection: (_, { lastAppliedQuery }) => lastAppliedQuery,
                invalidateReturn: () => null,
            },
        ],
        lastSelectionSource: [
            null as ChartAlternativeSource | null,
            {
                recordSelection: (_, { source }) => source,
                invalidateReturn: () => null,
            },
        ],
    }),
    selectors({
        editMode: [
            () => [(_, props) => props.editMode],
            (editMode: boolean | undefined): boolean | undefined => editMode,
        ],
        embedded: [() => [(_, props) => props.embedded], (embedded: boolean): boolean => embedded],
        inSharedMode: [
            () => [(_, props) => props.inSharedMode],
            (inSharedMode: boolean | undefined): boolean | undefined => inSharedMode,
        ],
        currentDisplay: [
            (s) => [s.display],
            (display: ChartDisplayType | null | undefined): ChartDisplayType =>
                display ?? ChartDisplayType.ActionsLineGraph,
        ],
        options: [
            (s) => [s.isTrends, s.isSingleSeriesOutput, s.querySource, s.series, s.featureFlags],
            (
                isTrends: boolean,
                isSingleSeriesOutput: boolean,
                querySource: ChartAlternativeQuerySource,
                series: TrendsQuery['series'] | null | undefined,
                featureFlags: FeatureFlagsSet
            ): ChartDisplayOptionGroup[] => {
                const trendsQuery = querySource && isTrendsQuery(querySource) ? querySource : null
                return getChartDisplayOptions({
                    isTrends,
                    hasSingleSeriesOutput: isSingleSeriesOutput,
                    hasTrendsFormula: !!(
                        trendsQuery?.trendsFilter?.formula ||
                        trendsQuery?.trendsFilter?.formulas?.length ||
                        trendsQuery?.trendsFilter?.formulaNodes?.length
                    ),
                    breakdown: trendsQuery?.breakdownFilter?.breakdown,
                    breakdowns: trendsQuery?.breakdownFilter?.breakdowns,
                    boxPlotMissingProperty: isBoxPlotMissingProperty(series as TrendsQuery['series']),
                    hasMetricInsight: !!featureFlags[FEATURE_FLAGS.METRIC_INSIGHT],
                })
            },
        ],
        alternatives: [
            (s) => [s.options, s.currentDisplay, s.querySource],
            (
                options: ChartDisplayOptionGroup[],
                currentDisplay: ChartDisplayType,
                querySource: ChartAlternativeQuerySource
            ): ChartDisplayOption[] =>
                getChartAlternatives(
                    options,
                    currentDisplay,
                    querySource && isTrendsQuery(querySource) ? querySource.breakdownFilter : undefined
                ),
        ],
        canShowAlternatives: [
            (s) => [
                s.featureFlags,
                s.editMode,
                s.embedded,
                s.inSharedMode,
                s.isInDashboardContext,
                s.canEditInsight,
                s.editingDisabledReason,
                s.isTrends,
                s.query,
                s.querySource,
            ],
            (
                featureFlags: FeatureFlagsSet,
                editMode: boolean | undefined,
                embedded: boolean,
                inSharedMode: boolean | undefined,
                isInDashboardContext: boolean,
                canEditInsight: boolean,
                editingDisabledReason: string | null,
                isTrends: boolean,
                query: Node | null,
                querySource: ChartAlternativeQuerySource
            ): boolean =>
                !!featureFlags[FEATURE_FLAGS.PRODUCT_ANALYTICS_CHART_ALTERNATIVES] &&
                !!editMode &&
                !embedded &&
                !inSharedMode &&
                !isInDashboardContext &&
                canEditInsight &&
                !editingDisabledReason &&
                isTrends &&
                !!query &&
                !!querySource &&
                isTrendsQuery(querySource),
        ],
        canSelectCharts: [
            (s) => [s.canShowAlternatives, s.insightDataLoading],
            (canShowAlternatives: boolean, insightDataLoading: boolean): boolean =>
                canShowAlternatives && !insightDataLoading,
        ],
        canReturn: [
            (s) => [s.canShowAlternatives, s.originalQuery, s.lastAppliedQuery, s.query],
            (
                canShowAlternatives: boolean,
                originalQuery: Node | null,
                lastAppliedQuery: Node | null,
                query: Node | null
            ): boolean =>
                canShowAlternatives &&
                !!originalQuery &&
                !!lastAppliedQuery &&
                !!query &&
                objectsEqual(query, lastAppliedQuery),
        ],
        canConfirmSelection: [
            (s) => [s.canSelectCharts, s.pendingSelection, s.query, s.currentDisplay, s.options],
            (
                canSelectCharts: boolean,
                pendingSelection: ChartAlternativeSelection | null,
                query: Node | null,
                currentDisplay: ChartDisplayType,
                options: ChartDisplayOptionGroup[]
            ): boolean =>
                canSelectCharts &&
                !!pendingSelection &&
                !!query &&
                objectsEqual(query, pendingSelection.query) &&
                pendingSelection.display !== currentDisplay &&
                !optionForDisplay(options, pendingSelection.display)?.disabledReason,
        ],
        selectionDisabledReason: [
            (s) => [s.canShowAlternatives, s.insightDataLoading, s.editingDisabledReason],
            (
                canShowAlternatives: boolean,
                insightDataLoading: boolean,
                editingDisabledReason: string | null
            ): string | undefined => {
                if (editingDisabledReason) {
                    return editingDisabledReason
                }
                if (insightDataLoading) {
                    return 'Chart is loading.'
                }
                return canShowAlternatives ? undefined : 'Chart types are unavailable.'
            },
        ],
        warning: [
            (s) => [s.pendingSelection, s.querySource],
            (
                pendingSelection: ChartAlternativeSelection | null,
                querySource: ChartAlternativeQuerySource
            ): ChartDisplayChangeWarning | null =>
                pendingSelection && querySource && isTrendsQuery(querySource)
                    ? getChartDisplayChangeWarning(pendingSelection.display, querySource)
                    : null,
        ],
    }),
    listeners(({ actions, cache, values }) => {
        const invalidateForExternalQuery = (query: Node | null): void => {
            if (cache.applyingSelection) {
                return
            }
            if (values.pendingSelection && !objectsEqual(query, values.pendingSelection.query)) {
                actions.clearPendingSelection()
            }
            if (values.lastAppliedQuery && !objectsEqual(query, values.lastAppliedQuery)) {
                actions.invalidateReturn()
            }
        }

        const applySelection = (display: ChartDisplayType, source: ChartAlternativeSource): void => {
            const option = optionForDisplay(values.options, display)
            if (
                !values.canSelectCharts ||
                !values.query ||
                !values.querySource ||
                !isTrendsQuery(values.querySource) ||
                !option ||
                option.disabledReason ||
                display === values.currentDisplay
            ) {
                return
            }

            const originalQuery = values.originalQuery ?? values.query
            const previousDisplay = values.currentDisplay
            cache.applyingSelection = true
            actions.updateQuerySource({
                trendsFilter: {
                    ...values.querySource.trendsFilter,
                    display,
                },
            })
            const appliedQuery = values.query
            cache.applyingSelection = false

            if (!appliedQuery) {
                return
            }
            actions.recordSelection(originalQuery, appliedQuery, source)
            posthog.capture('insight chart alternative selected', {
                previous_display: previousDisplay,
                display,
                source,
            })
        }

        return {
            openGallery: () => {
                if (!values.canSelectCharts) {
                    actions.closeGallery()
                }
            },
            selectChart: ({ display, source }) => {
                const option = optionForDisplay(values.options, display)
                if (
                    !values.canSelectCharts ||
                    !values.query ||
                    !values.querySource ||
                    !isTrendsQuery(values.querySource) ||
                    !option ||
                    option.disabledReason ||
                    display === values.currentDisplay
                ) {
                    return
                }
                if (source === 'gallery') {
                    actions.closeGallery()
                }
                const warning = getChartDisplayChangeWarning(display, values.querySource)
                if (warning) {
                    actions.requestSelection({ display, query: values.query, source })
                    return
                }
                applySelection(display, source)
            },
            confirmSelection: () => {
                const pendingSelection = values.pendingSelection
                if (!pendingSelection || !values.canConfirmSelection) {
                    actions.clearPendingSelection()
                    return
                }
                actions.clearPendingSelection()
                applySelection(pendingSelection.display, pendingSelection.source)
            },
            returnToOriginal: () => {
                if (!values.canReturn || !values.originalQuery) {
                    return
                }
                const previousDisplay = values.currentDisplay
                const originalSource = (values.originalQuery as { source?: TrendsQuery }).source
                const originalDisplay = isTrendsQuery(originalSource)
                    ? (originalSource.trendsFilter?.display ?? ChartDisplayType.ActionsLineGraph)
                    : ChartDisplayType.ActionsLineGraph
                const source = values.lastSelectionSource ?? 'strip'
                const originalQuery = values.originalQuery
                actions.invalidateReturn()
                actions.setQuery(originalQuery)
                posthog.capture('insight chart alternative returned', {
                    previous_display: previousDisplay,
                    display: originalDisplay,
                    source,
                })
            },
            setQuery: ({ query }) => invalidateForExternalQuery(query),
            saveInsightSuccess: () => actions.invalidateReturn(),
        }
    }),
])
