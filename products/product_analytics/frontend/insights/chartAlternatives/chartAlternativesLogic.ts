export const chartAlternativesLogic = kea<chartAlternativesLogicType>([
    props({} as ChartAlternativesLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'chartAlternatives', 'chartAlternativesLogic', key]),
    connect((props: ChartAlternativesLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            insightLogic(props),
            ['canEditInsight', 'editingDisabledReason', 'isInDashboardContext'],
            insightVizDataLogic(props),
            ['display', 'insightDataLoading', 'isSingleSeriesOutput', 'isTrends', 'query', 'querySource', 'series'],
        ],
        actions: [insightDataLogic(props), ['setQuery'], insightVizDataLogic(props), ['updateQuerySource']],
    })),
    actions({
        openGallery: true,
        closeGallery: true,
        toggleGallery: true,
        selectChart: (display: ChartDisplayType, source: ChartAlternativeSource) => ({ display, source }),
    }),
    reducers({
        galleryOpen: [
            false,
            {
                openGallery: () => true,
                closeGallery: () => false,
                toggleGallery: (state) => !state,
                selectChart: () => false,
            },
        ],
    }),
    selectors({
        editMode: [() => [(_, props) => props.editMode], (editMode: boolean | undefined) => editMode],
        embedded: [() => [(_, props) => props.embedded], (embedded: boolean) => embedded],
        inSharedMode: [() => [(_, props) => props.inSharedMode], (inSharedMode: boolean | undefined) => inSharedMode],
        currentDisplay: [
            (s) => [s.display],
            (display: ChartDisplayType | null | undefined): ChartDisplayType =>
                display ?? ChartDisplayType.ActionsLineGraph,
        ],
        trendsSource: [
            (s) => [s.querySource],
            (
                querySource:
                    | FunnelsQuery
                    | LifecycleQuery
                    | PathsQuery
                    | PathsV2Query
                    | RetentionQuery
                    | StickinessQuery
                    | TrendsQuery
                    | WebOverviewQuery
                    | WebStatsTableQuery
                    | null
            ): TrendsQuery | null => (querySource && isTrendsQuery(querySource) ? querySource : null),
        ],
        options: [
            (s) => [s.isTrends, s.isSingleSeriesOutput, s.trendsSource, s.series, s.featureFlags],
            (
                isTrends: boolean,
                isSingleSeriesOutput: boolean,
                trendsSource: TrendsQuery | null,
                series: (AnyEntityNode<AnyDataWarehouseNode> | GroupNode<DataWarehouseNode>)[] | null | undefined,
                featureFlags: FeatureFlagsSet
            ): ChartDisplayOptionGroup[] =>
                getChartDisplayOptions({
                    isTrends,
                    hasSingleSeriesOutput: isSingleSeriesOutput,
                    hasTrendsFormula: hasTrendsFormula(trendsSource?.trendsFilter),
                    breakdown: trendsSource?.breakdownFilter?.breakdown,
                    breakdowns: trendsSource?.breakdownFilter?.breakdowns,
                    boxPlotMissingProperty: isBoxPlotMissingProperty(series as TrendsQuery['series']),
                    hasMetricInsight: !!featureFlags[FEATURE_FLAGS.METRIC_INSIGHT],
                }),
        ],
        alternatives: [
            (s) => [s.options, s.trendsSource],
            (options: ChartDisplayOptionGroup[], trendsSource: TrendsQuery | null): ChartDisplayOption[] =>
                getChartAlternatives(options, trendsSource),
        ],
        currentOption: [
            (s) => [s.options, s.currentDisplay],
            (options: ChartDisplayOptionGroup[], currentDisplay: ChartDisplayType): ChartDisplayOption | undefined =>
                optionForDisplay(options, currentDisplay),
        ],
        isEditableSurface: [
            (s) => [
                s.editMode,
                s.embedded,
                s.inSharedMode,
                s.isInDashboardContext,
                s.canEditInsight,
                s.editingDisabledReason,
            ],
            (
                editMode: boolean | undefined,
                embedded: boolean,
                inSharedMode: boolean | undefined,
                isInDashboardContext: boolean,
                canEditInsight: boolean,
                editingDisabledReason: null
            ): boolean =>
                !!editMode &&
                !embedded &&
                !inSharedMode &&
                !isInDashboardContext &&
                canEditInsight &&
                !editingDisabledReason,
        ],
        canShowAlternatives: [
            (s) => [s.featureFlags, s.isEditableSurface, s.isTrends, s.query, s.trendsSource],
            (
                featureFlags: FeatureFlagsSet,
                isEditableSurface: boolean,
                isTrends: boolean,
                query: Node | null,
                trendsSource: TrendsQuery | null
            ): boolean =>
                !!featureFlags[FEATURE_FLAGS.PRODUCT_ANALYTICS_CHART_ALTERNATIVES] &&
                isEditableSurface &&
                isTrends &&
                !!query &&
                !!trendsSource,
        ],
        canSelectCharts: [
            (s) => [s.canShowAlternatives, s.insightDataLoading],
            (canShowAlternatives: boolean, insightDataLoading: boolean): boolean =>
                canShowAlternatives && !insightDataLoading,
        ],
        selectionDisabledReason: [
            (s) => [s.canShowAlternatives, s.insightDataLoading, s.editingDisabledReason],
            (
                canShowAlternatives: boolean,
                insightDataLoading: boolean,
                editingDisabledReason: null
            ): string | undefined => {
                if (editingDisabledReason) {
                    return editingDisabledReason
                }
                if (insightDataLoading) {
                    return 'Chart is loading.'
                }
                return canShowAlternatives ? undefined : 'Chart types are unavailable.'
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        openGallery: () => {
            if (!values.canSelectCharts) {
                actions.closeGallery()
            }
        },
        selectChart: ({ display, source }) => {
            const option = optionForDisplay(values.options, display)
            if (
                !values.canSelectCharts ||
                !values.trendsSource ||
                !option ||
                option.disabledReason ||
                display === values.currentDisplay
            ) {
                return
            }
            const previousDisplay = values.currentDisplay
            const next = applyChartDisplay(values.trendsSource, display)
            actions.updateQuerySource({ trendsFilter: next.trendsFilter, breakdownFilter: next.breakdownFilter })
            posthog.capture('insight chart alternative selected', {
                previous_display: previousDisplay,
                display,
                source,
            })
        },
        setQuery: () => {
            if (values.galleryOpen) {
                actions.closeGallery()
            }
        },
    })),
])
