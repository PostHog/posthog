export const chartTypeStripLogic: LogicWrapper<chartTypeStripLogicType> = kea<chartTypeStripLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'scene', 'chartTypes', 'chartTypeStripLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            insightVizDataLogic(props),
            [
                'display',
                'insightData',
                'insightDataError',
                'insightDataLoading',
                'isSingleSeriesOutput',
                'isTrends',
                'querySource',
                'series',
            ],
        ],
        actions: [insightVizDataLogic(props), ['loadDataSuccess', 'setInsightData', 'updateQuerySource']],
    })),
    actions({
        rememberTimeSeries: (entry: TimeSeriesEntry) => ({ entry }),
        selectChartType: (display: ChartDisplayType, source: ChartTypeSource) => ({ display, source }),
    }),
    reducers({
        rememberedTimeSeries: [
            null as TimeSeriesEntry | null,
            {
                rememberTimeSeries: (_, { entry }) => entry,
            },
        ],
    }),
    selectors({
        currentDisplay: [
            (s) => [s.display],
            (display: ChartDisplayType | null | undefined): ChartDisplayType =>
                display ?? ChartDisplayType.ActionsLineGraph,
        ],
        trendsSource: [
            (s) => [s.querySource],
            (querySource: insightVizDataLogicValues['querySource']): TrendsQuery | null =>
                querySource && isTrendsQuery(querySource) ? querySource : null,
        ],
        options: [
            (s) => [s.isTrends, s.isSingleSeriesOutput, s.trendsSource, s.series, s.featureFlags],
            (
                isTrends: boolean,
                isSingleSeriesOutput: boolean,
                trendsSource: TrendsQuery | null,
                series: insightVizDataLogicValues['series'],
                featureFlags: FeatureFlagsSet
            ): ChartDisplayOptionGroup[] =>
                getChartDisplayOptions({
                    isTrends,
                    hasSingleSeriesOutput: isSingleSeriesOutput,
                    hasTrendsFormula: hasTrendsFormula(trendsSource?.trendsFilter),
                    breakdown: trendsSource?.breakdownFilter?.breakdown,
                    breakdowns: trendsSource?.breakdownFilter?.breakdowns,
                    boxPlotMissingProperty: isBoxPlotMissingProperty(series as TrendsQuery['series']),
                    hasMetricInsight: !!featureFlags[FEATURE_FLAGS.METRIC_INSIGHT],
                    isComparing: !!trendsSource?.compareFilter?.compare,
                }),
        ],
        currentOption: [
            (s) => [s.options, s.currentDisplay],
            (options: ChartDisplayOptionGroup[], currentDisplay: ChartDisplayType): ChartDisplayOption | null =>
                options.flatMap((group) => group.options).find((option) => option.display === currentDisplay) ?? null,
        ],
        hasSinglePart: [
            (s) => [s.insightData],
            (insightData: Record<string, any> | null): boolean => {
                const rows = insightData?.result ?? insightData?.results
                return Array.isArray(rows) && rows.length === 1
            },
        ],
        suggestions: [
            (s) => [s.options, s.trendsSource, s.hasSinglePart],
            (
                options: ChartDisplayOptionGroup[],
                trendsSource: TrendsQuery | null,
                hasSinglePart: boolean
            ): ChartDisplayOption[] => {
                if (!trendsSource) {
                    return []
                }
                const candidates = hasSinglePart
                    ? options.map((group) => ({
                          ...group,
                          options: group.options.filter((option) => !PART_COMPARISON_DISPLAYS.includes(option.display)),
                      }))
                    : options
                return getChartAlternatives(candidates, trendsSource)
            },
        ],
        freeResponse: [
            (s) => [s.insightData],
            (insightData: Record<string, any> | null): AnyResponseType | null =>
                insightData?.result != null || insightData?.results != null ? (insightData as AnyResponseType) : null,
        ],
        hasResults: [
            (s) => [s.freeResponse],
            (freeResponse: AnyResponseType | null): boolean => !!freeResponse && hasPreviewData(freeResponse),
        ],
        stripState: [
            (s) => [s.trendsSource, s.insightDataLoading, s.insightDataError, s.hasResults],
            (
                trendsSource: TrendsQuery | null,
                insightDataLoading: boolean,
                insightDataError: Record<string, any> | null,
                hasResults: boolean
            ): ChartTypeStripState => {
                if (!trendsSource) {
                    return 'hidden'
                }
                if (insightDataLoading) {
                    return 'loading'
                }
                return insightDataError || !hasResults ? 'hidden' : 'ready'
            },
        ],
        timeSeriesKey: [
            (s) => [s.trendsSource],
            (trendsSource: TrendsQuery | null): string | null =>
                trendsSource
                    ? JSON.stringify(applyChartDisplay(trendsSource, ChartDisplayType.ActionsLineGraph))
                    : null,
        ],
        loadedTimeSeries: [
            (s) => [s.timeSeriesKey, s.currentDisplay, s.freeResponse, s.hasResults],
            (
                timeSeriesKey: string | null,
                currentDisplay: ChartDisplayType,
                freeResponse: AnyResponseType | null,
                hasResults: boolean
            ): TimeSeriesEntry | null =>
                timeSeriesKey && freeResponse && hasResults && RAW_TIME_SERIES_DISPLAYS.has(currentDisplay)
                    ? { key: timeSeriesKey, response: freeResponse }
                    : null,
        ],
        // A total value result has no buckets, so time series tiles reuse the last time series loaded for this query.
        timeSeriesResponse: [
            (s) => [s.timeSeriesKey, s.rememberedTimeSeries],
            (timeSeriesKey: string | null, rememberedTimeSeries: TimeSeriesEntry | null): AnyResponseType | null =>
                timeSeriesKey && rememberedTimeSeries?.key === timeSeriesKey ? rememberedTimeSeries.response : null,
        ],
        tiles: [
            (s) => [
                s.trendsSource,
                s.suggestions,
                s.freeResponse,
                s.timeSeriesResponse,
                s.stripState,
                (_, props) => keyForInsightLogicProps('new')(props),
            ],
            (
                trendsSource: TrendsQuery | null,
                suggestions: ChartDisplayOption[],
                freeResponse: AnyResponseType | null,
                timeSeriesResponse: AnyResponseType | null,
                stripState: ChartTypeStripState,
                logicKey: string
            ): ChartTypeTilePreview[] => {
                if (!trendsSource || stripState === 'hidden') {
                    return []
                }
                return suggestions.map((option) => {
                    const derived =
                        stripState === 'ready' && freeResponse
                            ? deriveChartPreview(option.display, trendsSource, freeResponse, timeSeriesResponse)
                            : null
                    return {
                        option,
                        query: plainPreviewQuery(previewVizNode(trendsSource, option.display)),
                        response: derived?.response ?? null,
                        sample: derived?.sample ?? false,
                        uniqueKey: `chart-type-strip-${logicKey}-${option.display}`,
                    }
                })
            },
        ],
    }),
    listeners(({ actions, values }) => {
        const rememberLoadedTimeSeries = (): void => {
            if (values.loadedTimeSeries) {
                actions.rememberTimeSeries(values.loadedTimeSeries)
            }
        }
        return {
            selectChartType: ({ display, source }) => {
                const option = values.options.flatMap((group) => group.options).find((o) => o.display === display)
                if (!values.trendsSource || !option || option.disabledReason || display === values.currentDisplay) {
                    return
                }
                const previousDisplay = values.currentDisplay
                const next = applyChartDisplay(values.trendsSource, display)
                actions.updateQuerySource({ trendsFilter: next.trendsFilter, breakdownFilter: next.breakdownFilter })
                // pinned: analytics event name, renaming breaks dashboards
                posthog.capture('insight chart alternative selected', {
                    previous_display: previousDisplay,
                    display,
                    source,
                })
            },
            loadDataSuccess: rememberLoadedTimeSeries,
            setInsightData: rememberLoadedTimeSeries,
        }
    }),
    // The insight can finish loading before this logic mounts.
    afterMount(({ actions, values }) => {
        if (values.loadedTimeSeries) {
            actions.rememberTimeSeries(values.loadedTimeSeries)
        }
    }),
])
