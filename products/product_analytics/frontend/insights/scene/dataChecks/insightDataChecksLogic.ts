export const insightDataChecksLogic: LogicWrapper<insightDataChecksLogicType> = kea<insightDataChecksLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'scene', 'dataChecks', 'insightDataChecksLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            insightVizDataLogic(props),
            ['insightDataLoading', 'querySource'],
            insightLogic(props),
            ['insight'],
            teamLogic,
            ['currentTeam'],
        ],
        actions: [
            insightVizDataLogic(props),
            ['loadDataFailure', 'loadDataSuccess', 'updateQuerySource'],
            maxGlobalLogic,
            ['askSidePanelMax'],
        ],
    })),
    actions({
        closeLabel: true,
        filterOutInternalUsers: true,
        reportDataChecksViewed: true,
        sendFixPrompt: (check: DataCheck, destination: DataCheckFixDestination) => ({ check, destination }),
    }),
    loaders(({ values }) => ({
        checksRun: [
            null as DataChecksRun | null,
            {
                loadChecksRun: async (_, breakpoint): Promise<DataChecksRun | null> => {
                    const queries = values.checksQueries
                    if (!queries) {
                        return null
                    }
                    const startedAt = performance.now()
                    let counts: DataCheckCounts | null = null
                    try {
                        const [checks, withoutInternalUsers] = await Promise.all([
                            performQuery(queries.checks),
                            queries.withoutInternalUsers ? performQuery(queries.withoutInternalUsers) : null,
                        ])
                        counts = dataCheckCountsFromRows(checks.results?.[0], withoutInternalUsers?.results?.[0])
                    } catch {
                        counts = null
                    }
                    await breakpoint(Math.max(MIN_CHECKING_MS - (performance.now() - startedAt), 0))
                    return counts ? { ok: true, counts } : { ok: false }
                },
            },
        ],
    })),
    reducers({
        labelHeldOpen: [
            false,
            {
                loadChecksRunSuccess: () => true,
                closeLabel: () => false,
            },
        ],
    }),
    selectors({
        checksContext: [
            (s) => [s.querySource, s.currentTeam],
            (
                querySource: insightVizDataLogicValues['querySource'],
                currentTeam: teamLogicValues['currentTeam']
            ): DataChecksContext => ({
                filtersInternalUsers: !!querySource?.filterTestAccounts,
                hasInternalUsersFilter: !!currentTeam?.test_account_filters?.length,
            }),
        ],
        checksQueries: [
            (s) => [s.querySource, s.checksContext],
            (
                querySource: insightVizDataLogicValues['querySource'],
                checksContext: DataChecksContext
            ): DataChecksQueries | null => buildDataChecksQueries(querySource, checksContext),
        ],
        counts: [
            (s) => [s.checksRun],
            (checksRun: DataChecksRun | null): DataCheckCounts | null => (checksRun?.ok ? checksRun.counts : null),
        ],
        // The checks run after the chart loads, so a loading chart means the last run is out of date.
        isChecking: [
            (s) => [s.insightDataLoading, s.checksRunLoading, s.checksRun],
            (insightDataLoading: boolean, checksRunLoading: boolean, checksRun: DataChecksRun | null): boolean =>
                insightDataLoading || checksRunLoading || !checksRun,
        ],
        checks: [
            (s) => [s.isChecking, s.counts, s.checksContext],
            (isChecking: boolean, counts: DataCheckCounts | null, checksContext: DataChecksContext): DataCheck[] => {
                if (isChecking) {
                    return unevaluatedDataChecks('pending')
                }
                return counts ? evaluateDataChecks(counts, checksContext) : unevaluatedDataChecks('skipped')
            },
        ],
        findings: [
            (s) => [s.checks],
            (checks: DataCheck[]): DataCheck[] =>
                checks.filter((check) => check.level === 'warning' || check.level === 'problem'),
        ],
        promptContext: [
            (s) => [s.querySource, s.insight, s.counts],
            (
                querySource: insightVizDataLogicValues['querySource'],
                insight: insightLogicValues['insight'],
                counts: DataCheckCounts | null
            ): DataCheckPromptContext | null => {
                const events = checkedEventNames(querySource)
                if (!events || !counts) {
                    return null
                }
                return {
                    insightUrl: insight.short_id
                        ? urls.absolute(urls.currentProject(urls.insightView(insight.short_id)))
                        : null,
                    events,
                    checkedEvents: counts.events,
                }
            },
        ],
        status: [
            (s) => [s.checksQueries, s.isChecking, s.counts, s.findings],
            (
                checksQueries: DataChecksQueries | null,
                isChecking: boolean,
                counts: DataCheckCounts | null,
                findings: DataCheck[]
            ): DataChecksStatus => {
                if (!checksQueries) {
                    return 'unavailable'
                }
                if (isChecking) {
                    return 'checking'
                }
                if (!counts) {
                    return 'failed'
                }
                if (!counts.events) {
                    return 'empty'
                }
                if (findings.some((check) => check.level === 'problem')) {
                    return 'problem'
                }
                return findings.length ? 'warning' : 'passed'
            },
        ],
        labelOpen: [
            (s) => [s.status, s.labelHeldOpen],
            (status: DataChecksStatus, labelHeldOpen: boolean): boolean => status === 'checking' || labelHeldOpen,
        ],
    }),
    listeners(({ actions, values }) => ({
        loadChecksRunSuccess: async (_, breakpoint) => {
            await breakpoint(LABEL_OPEN_MS)
            actions.closeLabel()
        },
        loadDataSuccess: () => {
            actions.loadChecksRun()
        },
        // The checks read the events directly, so they can run when the chart itself fails.
        loadDataFailure: () => {
            actions.loadChecksRun()
        },
        filterOutInternalUsers: () => {
            actions.updateQuerySource({ filterTestAccounts: true })
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight data check fix applied', { check: 'internal_users' })
        },
        sendFixPrompt: ({ check, destination }) => {
            if (!values.promptContext) {
                return
            }
            const prompt = dataCheckFixPrompt(check, values.promptContext)
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight data check fix prompt sent', { check: check.key, level: check.level, destination })
            if (destination === 'posthog_ai') {
                actions.askSidePanelMax(prompt)
            } else {
                void copyToClipboard(prompt, 'prompt for your agent')
            }
        },
        reportDataChecksViewed: () => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight data checks viewed', {
                status: values.status,
                findings: values.findings.map((check) => check.key),
            })
        },
    })),
    // The chart can finish loading before this logic mounts.
    afterMount(({ actions, values }) => {
        if (!values.insightDataLoading) {
            actions.loadChecksRun()
        }
    }),
])
