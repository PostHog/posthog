/** A run of the checks. A failed run is kept as a value, so the indicator can show it and offer a retry. */
export type DataChecksRun = { ok: true; counts: DataCheckCounts } | { ok: false }

export type DataChecksStatus = 'unavailable' | 'checking' | 'failed' | 'empty' | 'passed' | 'warning' | 'problem'

export type DataCheckFixDestination = 'posthog_ai' | 'clipboard'

/** A run that ends at once makes the mark flash, so the checking state lasts long enough to read. */
const MIN_CHECKING_MS = 1000
const LABEL_OPEN_MS = 2500

