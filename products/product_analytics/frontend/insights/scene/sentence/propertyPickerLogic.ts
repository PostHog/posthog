export type propertyPickerLogicType = MakeLogicType<
    propertyPickerLogicValues,
    propertyPickerLogicActions,
    PropertyPickerLogicProps
>

export const propertyPickerLogic: LogicWrapper<propertyPickerLogicType> = kea<propertyPickerLogicType>([
    props({} as PropertyPickerLogicProps),
    key((props) => props.pickerId),
    path((key) => ['products', 'product_analytics', 'insights', 'scene', 'sentence', 'propertyPickerLogic', key]),
    connect((props: PropertyPickerLogicProps) => ({
        values: [
            insightVizDataLogic(props.insightProps),
            ['allEventNames'],
            groupsModel,
            ['aggregationLabel', 'groupTypes'],
            teamLogic,
            ['currentProjectId'],
        ],
    })),
    actions({
        closePicker: true,
        loadProperties: (debounce: boolean) => ({ debounce }),
        loadPropertiesFailure: true,
        loadPropertiesSuccess: (groups: PropertyPickerGroup[], search: string) => ({ groups, search }),
        openPicker: true,
        setSearch: (search: string) => ({ search }),
    }),
    reducers({
        isOpen: [
            false,
            {
                openPicker: () => true,
                closePicker: () => false,
            },
        ],
        search: [
            '',
            {
                openPicker: () => '',
                setSearch: (_, { search }) => search,
            },
        ],
        groups: [
            null as PropertyPickerGroup[] | null,
            {
                openPicker: () => null,
                loadPropertiesSuccess: (_, { groups }) => groups,
            },
        ],
        loadedSearch: [
            null as string | null,
            {
                openPicker: () => null,
                loadPropertiesSuccess: (_, { search }) => search,
            },
        ],
        loadFailed: [
            false,
            {
                openPicker: () => false,
                loadProperties: () => false,
                loadPropertiesSuccess: () => false,
                loadPropertiesFailure: () => true,
            },
        ],
    }),
    selectors({
        sources: [
            (s) => [s.groupTypes, s.aggregationLabel],
            (
                groupTypes: propertyPickerLogicValues['groupTypes'],
                aggregationLabel: propertyPickerLogicValues['aggregationLabel']
            ): PropertyPickerSource[] => [
                {
                    value: 'event',
                    label: 'Event properties',
                    type: 'event',
                    taxonomicGroupType: TaxonomicFilterGroupType.EventProperties,
                },
                {
                    value: 'person',
                    label: 'Person properties',
                    type: 'person',
                    taxonomicGroupType: TaxonomicFilterGroupType.PersonProperties,
                },
                {
                    value: 'session',
                    label: 'Session properties',
                    type: 'session',
                    taxonomicGroupType: TaxonomicFilterGroupType.SessionProperties,
                },
                ...Array.from(groupTypes.values()).map(
                    (groupType): PropertyPickerSource => ({
                        value: `group_${groupType.group_type_index}`,
                        label: `${capitalizeFirstLetter(aggregationLabel(groupType.group_type_index).singular)} properties`,
                        type: 'group',
                        groupTypeIndex: groupType.group_type_index,
                        taxonomicGroupType:
                            `${TaxonomicFilterGroupType.GroupsPrefix}_${groupType.group_type_index}` as TaxonomicFilterGroupType,
                    })
                ),
            ],
        ],
        isStale: [
            (s) => [s.groups, s.loadedSearch, s.search],
            (groups: PropertyPickerGroup[] | null, loadedSearch: string | null, search: string): boolean =>
                groups !== null && loadedSearch !== search.trim(),
        ],
        status: [
            (s) => [s.loadFailed, s.groups, s.isStale],
            (loadFailed: boolean, groups: PropertyPickerGroup[] | null, isStale: boolean): PropertyPickerStatus => {
                if (loadFailed) {
                    return 'failed'
                }
                if (groups?.some((group) => group.items.length > 0)) {
                    return 'ready'
                }
                return groups === null || isStale ? 'loading' : 'empty'
            },
        ],
        visibleGroups: [
            (s) => [s.status, s.groups],
            (status: PropertyPickerStatus, groups: PropertyPickerGroup[] | null): PropertyPickerGroup[] =>
                status === 'ready' && groups ? groups.filter((group) => group.items.length > 0) : [],
        ],
    }),
    listeners(({ actions, values, props }) => ({
        openPicker: () => {
            actions.loadProperties(false)
        },
        setSearch: () => {
            if (values.isOpen) {
                actions.loadProperties(true)
            }
        },
        loadProperties: async ({ debounce }, breakpoint) => {
            if (debounce) {
                await breakpoint(SEARCH_DEBOUNCE_MS)
            }
            const request: PropertyPickerRequest = {
                projectId: String(values.currentProjectId),
                search: values.search.trim(),
                numericOnly: !!props.numericOnly,
                eventNames: values.allEventNames,
            }
            let groups: PropertyPickerGroup[]
            try {
                groups = await Promise.all(values.sources.map((source) => loadPropertyPickerGroup(source, request)))
            } catch {
                breakpoint()
                actions.loadPropertiesFailure()
                return
            }
            breakpoint()
            actions.loadPropertiesSuccess(groups, request.search)
        },
    })),
])
