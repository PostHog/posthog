export const PROPERTY_PICKER_GROUP_LIMIT = 50

const SEARCH_DEBOUNCE_MS = 250

export interface PropertyPickerLogicProps {
    pickerId: string
    insightProps: InsightLogicProps
    numericOnly?: boolean
}

export interface PropertyPickerSource {
    value: string
    label: string
    type: PickedProperty['type']
    groupTypeIndex?: number
    taxonomicGroupType: TaxonomicFilterGroupType
}

export interface PropertyPickerGroup {
    value: string
    label: string
    items: PickedProperty[]
    total: number
}

export type PropertyPickerStatus = 'loading' | 'failed' | 'empty' | 'ready'

type PropertyDefinitionRow = Pick<EnterprisePropertyDefinitionApi, 'name' | 'property_type'>

interface PropertyPickerRequest {
    projectId: string
    search: string
    numericOnly: boolean
    eventNames: string[]
}

function toPropertyType(propertyType: PropertyDefinitionRow['property_type']): PropertyType | undefined {
    return Object.values(PropertyType).find((knownType) => knownType === propertyType)
}

function toPickedProperty(source: PropertyPickerSource, definition: PropertyDefinitionRow): PickedProperty {
    return {
        key: definition.name,
        type: source.type,
        ...(source.groupTypeIndex === undefined ? {} : { groupTypeIndex: source.groupTypeIndex }),
        label: getCoreFilterDefinition(definition.name, source.taxonomicGroupType)?.label || definition.name,
        propertyType: toPropertyType(definition.property_type),
    }
}

async function loadPropertyPickerGroup(
    source: PropertyPickerSource,
    { projectId, search, numericOnly, eventNames }: PropertyPickerRequest
): Promise<PropertyPickerGroup> {
    const narrowing = {
        ...(search ? { search } : {}),
        ...(numericOnly ? { is_numerical: true } : {}),
    }

    if (source.type === 'session') {
        // Session properties are columns of the sessions table, so the property definitions endpoint returns none.
        const response = await api.get<{ results: PropertyDefinitionRow[] }>(
            combineUrl(`api/projects/${projectId}/sessions/property_definitions/`, narrowing).url
        )
        return {
            value: source.value,
            label: source.label,
            items: response.results.map((definition) => toPickedProperty(source, definition)),
            total: response.results.length,
        }
    }

    const response = await propertyDefinitionsList(projectId, {
        ...narrowing,
        type: source.type,
        limit: PROPERTY_PICKER_GROUP_LIMIT,
        exclude_hidden: true,
        exclude_restricted: true,
        ...(source.type === 'group' ? { group_type_index: source.groupTypeIndex } : {}),
        ...(source.type === 'event'
            ? {
                  ...(search ? {} : { is_feature_flag: false }),
                  ...(eventNames.length ? { event_names: JSON.stringify(eventNames) } : {}),
              }
            : {}),
    })
    return {
        value: source.value,
        label: source.label,
        items: response.results.map((definition) => toPickedProperty(source, definition)),
        total: response.count,
    }
}

