export type insightSentenceLogicType = MakeLogicType<
    insightSentenceLogicValues,
    insightSentenceLogicActions,
    InsightLogicProps
>

export const insightSentenceLogic: LogicWrapper<insightSentenceLogicType> = kea<insightSentenceLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'scene', 'sentence', 'insightSentenceLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            insightVizDataLogic(props),
            ['querySource', 'enabledIntervals'],
            mathsLogic,
            ['mathDefinitions'],
            trendsDataLogic(props),
            ['indexedResults', 'getTrendsColor'],
        ],
        actions: [insightVizDataLogic(props), ['updateQuerySource', 'updateDateRange', 'updateCompareFilter']],
    })),
    actions({
        addSeries: (groupType: TaxonomicFilterGroupType, value: SeriesValue, name?: string) => ({
            groupType,
            value,
            name,
        }),
        changeDateRange: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        changeInterval: (interval: IntervalType) => ({ interval }),
        changeSeriesEvent: (
            seriesIndex: number,
            groupType: TaxonomicFilterGroupType,
            value: SeriesValue,
            name?: string
        ) => ({ seriesIndex, groupType, value, name }),
        changeSeriesMath: (seriesIndex: number, mathType: string) => ({ seriesIndex, mathType }),
        changeSeriesPropertyMath: (
            seriesIndex: number,
            mathType: string,
            property: string,
            propertyGroupType: TaxonomicFilterGroupType
        ) => ({ seriesIndex, mathType, property, propertyGroupType }),
        changeSeriesExpression: (seriesIndex: number, expression: string) => ({ seriesIndex, expression }),
        changeSplitBins: (splitIndex: number, bins: number) => ({ splitIndex, bins }),
        changeSplitLimit: (limit: number) => ({ limit }),
        removeSplitAt: (splitIndex: number) => ({ splitIndex }),
        combineSeriesEvent: (
            seriesIndex: number,
            groupType: TaxonomicFilterGroupType,
            value: SeriesValue,
            name?: string
        ) => ({ seriesIndex, groupType, value, name }),
        duplicateSeries: (seriesIndex: number) => ({ seriesIndex }),
        removeSeries: (seriesIndex: number) => ({ seriesIndex }),
        removeSplit: true,
        renameSeries: (seriesIndex: number, name: string) => ({ seriesIndex, name }),
        setFormulaPending: (pending: boolean) => ({ pending }),
        setFormulas: (formulas: string[]) => ({ formulas }),
        setPendingFilterSeriesIndex: (seriesIndex: number | null) => ({ seriesIndex }),
        setRenamingSeriesIndex: (seriesIndex: number | null) => ({ seriesIndex }),
        setSeriesExpanded: (expanded: boolean) => ({ expanded }),
        splitCombinedSeries: (seriesIndex: number) => ({ seriesIndex }),
        toggleCompare: true,
    }),
    reducers({
        seriesExpanded: [
            false,
            {
                setSeriesExpanded: (_, { expanded }) => expanded,
                // A new event would land among the counted ones, so show every event after one is added.
                addSeries: () => true,
                duplicateSeries: () => true,
                splitCombinedSeries: () => true,
            },
        ],
        // The indexes below point at events, so removing an event clears them.
        pendingFilterSeriesIndex: [
            null as number | null,
            {
                setPendingFilterSeriesIndex: (_, { seriesIndex }) => seriesIndex,
                removeSeries: () => null,
            },
        ],
        renamingSeriesIndex: [
            null as number | null,
            {
                setRenamingSeriesIndex: (_, { seriesIndex }) => seriesIndex,
                renameSeries: () => null,
                removeSeries: () => null,
            },
        ],
        formulaPending: [
            false,
            {
                setFormulaPending: (_, { pending }) => pending,
                setFormulas: () => false,
            },
        ],
    }),
    selectors({
        overriddenSlots: [
            () => [(_, props) => props.filtersOverride],
            (filtersOverride: DashboardFilter | null | undefined): SentenceSlot[] => {
                const slots: SentenceSlot[] = []
                if (filtersOverride?.date_from != null || filtersOverride?.date_to != null) {
                    slots.push('dateRange')
                }
                if (filtersOverride?.interval != null) {
                    slots.push('interval')
                }
                if (filtersOverride?.properties?.length) {
                    slots.push('filters')
                }
                const split = filtersOverride?.breakdown_filter
                if (split?.breakdown != null || split?.breakdowns?.length) {
                    slots.push('split')
                }
                return slots
            },
        ],
        trendsQuery: [
            (s) => [s.querySource],
            (querySource: insightSentenceLogicValues['querySource']): TrendsQuery | null =>
                querySource && isTrendsQuery(querySource) ? querySource : null,
        ],
        sentenceInput: [
            (s) => [s.trendsQuery, s.mathDefinitions],
            (
                trendsQuery: TrendsQuery | null,
                mathDefinitions: insightSentenceLogicValues['mathDefinitions']
            ): SentenceInput | null => (trendsQuery ? sentenceInputFromQuery(trendsQuery, mathDefinitions) : null),
        ],
        sentence: [
            (s) => [s.sentenceInput, s.seriesExpanded, s.pendingFilterSeriesIndex, s.formulaPending],
            (
                sentenceInput: SentenceInput | null,
                seriesExpanded: boolean,
                pendingFilterSeriesIndex: number | null,
                formulaPending: boolean
            ): Sentence | null =>
                sentenceInput
                    ? buildSentence(sentenceInput, { seriesExpanded, pendingFilterSeriesIndex, formulaPending })
                    : null,
        ],
        formulas: [
            (s) => [s.trendsQuery],
            (trendsQuery: TrendsQuery | null): string[] => {
                const trendsFilter = trendsQuery?.trendsFilter
                const fromNodes = (trendsFilter?.formulaNodes ?? []).flatMap((node) =>
                    node.formula?.trim() ? [node.formula.trim()] : []
                )
                if (fromNodes.length) {
                    return fromNodes
                }
                if (trendsFilter?.formulas?.length) {
                    return trendsFilter.formulas
                }
                return trendsFilter?.formula ? [trendsFilter.formula] : []
            },
        ],
        collapsedSeriesLabels: [
            (s) => [s.sentenceInput],
            (sentenceInput: SentenceInput | null): string[] =>
                sentenceInput ? collapsedSeries(sentenceInput).map(seriesLabel) : [],
        ],
        seriesColors: [
            (s) => [s.trendsQuery, s.sentenceInput, s.indexedResults, s.getTrendsColor],
            (
                trendsQuery: TrendsQuery | null,
                sentenceInput: SentenceInput | null,
                indexedResults: IndexedTrendResult[],
                getTrendsColor: (dataset: IndexedTrendResult) => string
            ): (string | null)[] => {
                const series = trendsQuery?.series ?? []
                // The color tells events apart, so one event needs none. A split or a formula draws lines that do
                // not map to one event each, so then no event owns a color either.
                if (
                    !trendsQuery ||
                    series.length < 2 ||
                    hasBreakdownFilter(trendsQuery.breakdownFilter) ||
                    sentenceInput?.formulas.length
                ) {
                    return series.map(() => null)
                }
                return series.map((_, index) => {
                    const result = indexedResults.find(
                        (candidate) => candidate.action?.order === index && candidate.compare_label !== 'previous'
                    )
                    return result ? getTrendsColor(result) : null
                })
            },
        ],
        seriesMathTypes: [
            (s) => [s.trendsQuery],
            (trendsQuery: TrendsQuery | null): string[] =>
                (trendsQuery?.series ?? []).map((node) => apiValueToMathType(node.math, node.math_group_type_index)),
        ],
        propertyMeasureOptions: [
            (s) => [s.mathDefinitions],
            (mathDefinitions: insightSentenceLogicValues['mathDefinitions']): MeasureOption[] =>
                Object.values(PropertyMathType).flatMap((value) => {
                    const definition = mathDefinitions[value]
                    return definition ? [{ value, label: definition.name }] : []
                }),
        ],
        perUserMeasureOptions: [
            (s) => [s.mathDefinitions],
            (mathDefinitions: insightSentenceLogicValues['mathDefinitions']): MeasureOption[] =>
                Object.values(CountPerActorMathType).flatMap((value) => {
                    const definition = mathDefinitions[value]
                    return definition ? [{ value, label: definition.name }] : []
                }),
        ],
        measureOptions: [
            (s) => [s.mathDefinitions],
            (mathDefinitions: insightSentenceLogicValues['mathDefinitions']): MeasureOption[] => [
                ...BASE_MEASURES.flatMap((value) => {
                    const definition = mathDefinitions[value]
                    return definition ? [{ value, label: definition.name }] : []
                }),
                ...Object.entries(mathDefinitions).flatMap(([value, definition]) =>
                    definition && value.startsWith(`${GroupMathType.UniqueGroup}::`)
                        ? [{ value, label: `Unique ${definition.name}` }]
                        : []
                ),
            ],
        ],
    }),
    listeners(({ actions, values }) => ({
        changeInterval: ({ interval }) => {
            actions.updateQuerySource({ interval } as QuerySourceUpdate)
        },
        changeDateRange: ({ dateFrom, dateTo }) => {
            actions.updateDateRange({ date_from: dateFrom, date_to: dateTo })
        },
        toggleCompare: () => {
            actions.updateCompareFilter({ compare: !values.trendsQuery?.compareFilter?.compare })
        },
        changeSeriesMath: ({ seriesIndex, mathType }) => {
            const query = values.trendsQuery
            if (!query) {
                return
            }
            const { math, math_group_type_index } = mathTypeToApiValues(mathType)
            const series = query.series.map((node, index) =>
                index === seriesIndex
                    ? {
                          ...node,
                          math,
                          math_group_type_index,
                          math_property: undefined,
                          math_property_type: undefined,
                          math_hogql: undefined,
                      }
                    : node
            )
            actions.updateQuerySource({ series } as QuerySourceUpdate)
        },
        changeSeriesPropertyMath: ({ seriesIndex, mathType, property, propertyGroupType }) => {
            const query = values.trendsQuery
            if (!query) {
                return
            }
            const series = query.series.map((node, index) =>
                index === seriesIndex
                    ? {
                          ...node,
                          math: mathType,
                          math_group_type_index: undefined,
                          math_property: property,
                          math_property_type: propertyGroupType,
                          math_hogql: undefined,
                      }
                    : node
            )
            actions.updateQuerySource({ series } as QuerySourceUpdate)
        },
        changeSeriesEvent: ({ seriesIndex, groupType, value, name }) => {
            const query = values.trendsQuery
            const node = query ? seriesNodeFromPick(groupType, value, name, query.series[seriesIndex]) : null
            if (!query || !node) {
                return
            }
            const series = query.series.map((existing, index) => (index === seriesIndex ? node : existing))
            actions.updateQuerySource({ series } as QuerySourceUpdate)
        },
        addSeries: ({ groupType, value, name }) => {
            const query = values.trendsQuery
            const node = seriesNodeFromPick(groupType, value, name)
            if (!query || !node) {
                return
            }
            actions.updateQuerySource({ series: [...query.series, node] } as QuerySourceUpdate)
        },
        removeSplit: () => {
            actions.updateQuerySource({ breakdownFilter: undefined } as QuerySourceUpdate)
        },
        removeSplitAt: ({ splitIndex }) => {
            const breakdownFilter = values.trendsQuery?.breakdownFilter
            const remaining = breakdownFilter?.breakdowns?.filter((_, index) => index !== splitIndex) ?? []
            actions.updateQuerySource({
                breakdownFilter: remaining.length ? { ...breakdownFilter, breakdowns: remaining } : undefined,
            } as QuerySourceUpdate)
        },
        changeSplitBins: ({ splitIndex, bins }) => {
            const breakdownFilter = values.trendsQuery?.breakdownFilter
            if (!breakdownFilter) {
                return
            }
            // An older insight keeps one split in the single-split fields.
            const next = breakdownFilter.breakdowns?.length
                ? {
                      ...breakdownFilter,
                      breakdowns: breakdownFilter.breakdowns.map((split, index) =>
                          index === splitIndex ? { ...split, histogram_bin_count: bins } : split
                      ),
                  }
                : { ...breakdownFilter, breakdown_histogram_bin_count: bins }
            actions.updateQuerySource({ breakdownFilter: next } as QuerySourceUpdate)
        },
        changeSplitLimit: ({ limit }) => {
            const breakdownFilter = values.trendsQuery?.breakdownFilter
            if (!breakdownFilter) {
                return
            }
            actions.updateQuerySource({
                breakdownFilter: { ...breakdownFilter, breakdown_limit: limit },
            } as QuerySourceUpdate)
        },
        changeSeriesExpression: ({ seriesIndex, expression }) => {
            const query = values.trendsQuery
            if (!query || !expression.trim()) {
                return
            }
            const series = query.series.map((node, index) =>
                index === seriesIndex
                    ? {
                          ...node,
                          math: HogQLMathType.HogQL,
                          math_hogql: expression.trim(),
                          math_group_type_index: undefined,
                          math_property: undefined,
                          math_property_type: undefined,
                      }
                    : node
            )
            actions.updateQuerySource({ series } as QuerySourceUpdate)
        },
        duplicateSeries: ({ seriesIndex }) => {
            const query = values.trendsQuery
            const node = query?.series[seriesIndex]
            if (!query || !node) {
                return
            }
            const series = [
                ...query.series.slice(0, seriesIndex + 1),
                { ...node },
                ...query.series.slice(seriesIndex + 1),
            ]
            actions.updateQuerySource({ series } as QuerySourceUpdate)
        },
        renameSeries: ({ seriesIndex, name }) => {
            const query = values.trendsQuery
            if (!query) {
                return
            }
            const series = query.series.map((node, index) =>
                index === seriesIndex ? { ...node, custom_name: name.trim() || undefined } : node
            )
            actions.updateQuerySource({ series } as QuerySourceUpdate)
        },
        combineSeriesEvent: ({ seriesIndex, groupType, value, name }) => {
            const query = values.trendsQuery
            const existing = query?.series[seriesIndex]
            const added = seriesNodeFromPick(groupType, value, name)
            if (!query || !existing || !added) {
                return
            }
            const group = isGroupNode(existing) ? existing : seriesNodeToGroupNode(existing)
            const nodes = [...group.nodes, added]
            const combined = { ...group, nodes, name: nodes.map((node) => node.name).join(', ') }
            const series = query.series.map((node, index) => (index === seriesIndex ? combined : node))
            actions.updateQuerySource({ series } as QuerySourceUpdate)
        },
        splitCombinedSeries: ({ seriesIndex }) => {
            const query = values.trendsQuery
            const group = query?.series[seriesIndex]
            if (!query || !group || !isGroupNode(group)) {
                return
            }
            // Each event keeps the measure the combined line had.
            const separate = group.nodes.map((node) => ({
                ...node,
                math: group.math,
                math_property: group.math_property,
                math_property_type: group.math_property_type,
                math_hogql: group.math_hogql,
                math_group_type_index: group.math_group_type_index,
            }))
            const series = [...query.series.slice(0, seriesIndex), ...separate, ...query.series.slice(seriesIndex + 1)]
            actions.updateQuerySource({ series } as QuerySourceUpdate)
        },
        setFormulas: ({ formulas }) => {
            const query = values.trendsQuery
            if (!query) {
                return
            }
            const formulaNodes = formulas.flatMap((formula) => (formula.trim() ? [{ formula: formula.trim() }] : []))
            actions.updateQuerySource({
                trendsFilter: {
                    ...query.trendsFilter,
                    formula: undefined,
                    formulas: undefined,
                    formulaNodes: formulaNodes.length ? formulaNodes : undefined,
                },
            } as QuerySourceUpdate)
        },
        removeSeries: ({ seriesIndex }) => {
            const query = values.trendsQuery
            if (!query || query.series.length < 2) {
                return
            }
            const series = query.series.filter((_, index) => index !== seriesIndex)
            actions.updateQuerySource({ series } as QuerySourceUpdate)
        },
    })),
])
