export const EVENT_PICKER_GROUP_LIMIT = 100

const SEARCH_DEBOUNCE_MS = 250

export interface EventPickerLogicProps {
    pickerKey: string
    groupType?: TaxonomicFilterGroupType
    value?: string | number | null
}

export interface EventPickerItem {
    id: string
    groupType: TaxonomicFilterGroupType
    value: string | number | null
    name?: string
    label: string
}

// A type alias, because the combobox group type has an index signature that an interface does not satisfy.
export type EventPickerGroup = {
    value: 'events' | 'actions'
    items: EventPickerItem[]
    loading: boolean
    capped: boolean
}

export interface EventPickerEventsPage {
    search: string
    events: EnterpriseEventDefinitionApi[]
    hasMore: boolean
}

const ALL_EVENTS_ITEM: EventPickerItem = {
    id: 'all-events',
    groupType: TaxonomicFilterGroupType.Events,
    value: null,
    name: 'All events',
    label: 'All events',
}

function eventItem(name: string): EventPickerItem {
    return {
        id: `event:${name}`,
        groupType: TaxonomicFilterGroupType.Events,
        value: name,
        name,
        label: getCoreFilterDefinition(name, TaxonomicFilterGroupType.Events)?.label ?? name,
    }
}

function actionItem(action: ActionType): EventPickerItem {
    return {
        id: `action:${action.id}`,
        groupType: TaxonomicFilterGroupType.Actions,
        value: action.id,
        name: action.name ?? undefined,
        label: action.name || `Action ${action.id}`,
    }
}

function matchesSearch(item: EventPickerItem, searchTerms: string[]): boolean {
    const text = `${item.label} ${item.name ?? ''}`.toLowerCase()
    return searchTerms.every((term) => text.includes(term))
}

