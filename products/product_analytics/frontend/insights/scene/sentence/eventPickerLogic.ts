export type eventPickerLogicType = MakeLogicType<
    eventPickerLogicValues,
    eventPickerLogicActions,
    EventPickerLogicProps,
    eventPickerLogicMeta
>

export const eventPickerLogic: LogicWrapper<eventPickerLogicType> = kea<eventPickerLogicType>([
    props({} as EventPickerLogicProps),
    key((props) => props.pickerKey),
    path((key) => ['products', 'product_analytics', 'insights', 'scene', 'sentence', 'eventPickerLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], actionsModel({}), ['actions', 'actionsLoaded', 'actionsLoading']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
    }),
    loaders(({ values }) => ({
        eventsPage: [
            null as EventPickerEventsPage | null,
            {
                loadEvents: async (_payload: void, breakpoint) => {
                    const search = values.search
                    const teamId = values.currentTeamId
                    if (!teamId) {
                        return { search, events: [], hasMore: false }
                    }
                    const response = await eventDefinitionsList(String(teamId), {
                        search: search.trim() || undefined,
                        event_type: EventDefinitionsListEventType.Event,
                        exclude_hidden: true,
                        limit: EVENT_PICKER_GROUP_LIMIT,
                    }).catch((error: unknown) => {
                        breakpoint()
                        throw error
                    })
                    breakpoint()
                    return { search, events: response.results, hasMore: !!response.next }
                },
            },
        ],
    })),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        eventsLoadFailed: [
            false,
            {
                loadEvents: () => false,
                loadEventsSuccess: () => false,
                loadEventsFailure: () => true,
            },
        ],
    }),
    selectors({
        selectedItem: [
            (s) => [(_, props) => props.groupType, (_, props) => props.value, s.actions],
            (
                groupType: TaxonomicFilterGroupType | undefined,
                value: string | number | null | undefined,
                actions
            ): EventPickerItem | null => {
                if (groupType === TaxonomicFilterGroupType.Actions) {
                    const action = actions.find((candidate) => candidate.id === value)
                    return action ? actionItem(action) : null
                }
                if (groupType === TaxonomicFilterGroupType.Events) {
                    return typeof value === 'string' ? eventItem(value) : ALL_EVENTS_ITEM
                }
                return null
            },
        ],
        searchTerms: [(s) => [s.search], (search): string[] => search.toLowerCase().split(/\s+/).filter(Boolean)],
        eventsStale: [(s) => [s.search, s.eventsPage], (search, eventsPage): boolean => eventsPage?.search !== search],
        eventsPending: [
            (s) => [s.eventsStale, s.eventsPageLoading, s.eventsLoadFailed],
            (eventsStale, eventsPageLoading, eventsLoadFailed): boolean =>
                !eventsLoadFailed && (eventsStale || eventsPageLoading),
        ],
        eventItems: [
            (s) => [s.eventsPage, s.eventsStale, s.searchTerms],
            (eventsPage, eventsStale, searchTerms): EventPickerItem[] => {
                const items = (eventsPage?.events ?? []).map((event) => eventItem(event.name))
                // Results for an older search stay on screen until the server answers, narrowed to what still matches.
                return eventsStale ? items.filter((item) => matchesSearch(item, searchTerms)) : items
            },
        ],
        actionItems: [
            (s) => [s.actions, s.searchTerms],
            (actions, searchTerms): EventPickerItem[] =>
                actions
                    .filter((action) => !action.deleted)
                    .map(actionItem)
                    .filter((item) => matchesSearch(item, searchTerms)),
        ],
        eventsGroup: [
            (s) => [s.eventItems, s.searchTerms, s.eventsPending, s.eventsStale, s.eventsPage],
            (eventItems, searchTerms, eventsPending, eventsStale, eventsPage): EventPickerGroup => ({
                value: 'events',
                items: matchesSearch(ALL_EVENTS_ITEM, searchTerms) ? [ALL_EVENTS_ITEM, ...eventItems] : eventItems,
                loading: eventsPending && eventItems.length === 0,
                capped: !eventsStale && !!eventsPage?.hasMore,
            }),
        ],
        actionsGroup: [
            (s) => [s.actionItems, s.actionsLoaded, s.actionsLoading],
            (actionItems, actionsLoaded, actionsLoading): EventPickerGroup => ({
                value: 'actions',
                items: actionItems.slice(0, EVENT_PICKER_GROUP_LIMIT),
                loading: actionsLoading && !actionsLoaded,
                capped: actionItems.length > EVENT_PICKER_GROUP_LIMIT,
            }),
        ],
        groups: [
            (s) => [s.eventsGroup, s.actionsGroup],
            (eventsGroup, actionsGroup): EventPickerGroup[] =>
                [eventsGroup, actionsGroup].filter((group) => group.items.length > 0 || group.loading),
        ],
    }),
    listeners(({ actions }) => ({
        setSearch: async (_, breakpoint) => {
            await breakpoint(SEARCH_DEBOUNCE_MS)
            actions.loadEvents()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadEvents()
    }),
])
