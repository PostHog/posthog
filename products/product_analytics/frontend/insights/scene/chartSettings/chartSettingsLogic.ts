export const chartSettingsLogic: LogicWrapper<chartSettingsLogicType> = kea<chartSettingsLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'scene', 'chartSettings', 'chartSettingsLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            insightVizDataLogic(props),
            [
                'annotationsScope',
                'breakdownFilter',
                'display',
                'goalLines',
                'hasLegend',
                'interval',
                'isNonTimeSeriesDisplay',
                'isTrends',
                'legendPosition',
                'showAlertThresholdLines',
                'showAnnotations',
                'showLabelOnSeries',
                'showLegend',
                'showMultipleYAxes',
                'showPercentStackView',
                'showValuesOnSeries',
                'supportsBarValueStacking',
                'supportsPercentStackView',
                'supportsResultCustomizationBy',
                'supportsValueOnSeries',
                'trendsFilter',
                'usesInChartLegend',
                'yAxisScaleType',
            ],
            trendsDataLogic(props),
            [
                'confidenceLevel',
                'mightContainFractionalNumbers',
                'movingAverageIntervals',
                'pieChartVizOptions',
                'resultCustomizationBy',
                'showConfidenceIntervals',
                'showMovingAverage',
            ],
        ],
        actions: [insightVizDataLogic(props), ['updateQuerySource', 'updateVizSpecificOptions']],
    })),
    actions({
        addGoalLine: true,
        changeGoalLine: (index: number, changes: Partial<GoalLine>) => ({ index, changes }),
        changeSetting: (id: ChartSettingId, value: ChartSettingValue) => ({ id, value }),
        changeTrendsFilter: (changes: Partial<TrendsFilter>) => ({ changes }),
        removeGoalLine: (index: number) => ({ index }),
    }),
    selectors({
        // A selector takes at most 16 inputs, so the input for the settings is built in three parts.
        chartInput: [
            (s) => [
                s.display,
                s.trendsFilter,
                s.interval,
                s.breakdownFilter,
                s.isNonTimeSeriesDisplay,
                s.yAxisScaleType,
            ],
            (
                display: insightVizDataLogicValues['display'],
                trendsFilter: insightVizDataLogicValues['trendsFilter'],
                interval: insightVizDataLogicValues['interval'],
                breakdownFilter: insightVizDataLogicValues['breakdownFilter'],
                isNonTimeSeriesDisplay: boolean,
                yAxisScaleType: insightVizDataLogicValues['yAxisScaleType']
            ): ChartInput => ({
                display,
                trendsFilter,
                interval,
                hasBreakdown: hasBreakdownFilter(breakdownFilter),
                isNonTimeSeriesDisplay,
                yAxisScaleType,
            }),
        ],
        generalInput: [
            (s) => [
                s.hasLegend,
                s.usesInChartLegend,
                s.showLegend,
                s.legendPosition,
                s.supportsValueOnSeries,
                s.showValuesOnSeries,
                s.showLabelOnSeries,
                s.supportsPercentStackView,
                s.showPercentStackView,
                s.supportsBarValueStacking,
                s.supportsResultCustomizationBy,
                s.resultCustomizationBy,
                s.showAnnotations,
                s.annotationsScope,
                s.pieChartVizOptions,
            ],
            (
                hasLegend: boolean,
                usesInChartLegend: boolean,
                showLegend: insightVizDataLogicValues['showLegend'],
                legendPosition: insightVizDataLogicValues['legendPosition'],
                supportsValueOnSeries: boolean,
                showValuesOnSeries: insightVizDataLogicValues['showValuesOnSeries'],
                showLabelOnSeries: insightVizDataLogicValues['showLabelOnSeries'],
                supportsPercentStackView: boolean,
                showPercentStackView: insightVizDataLogicValues['showPercentStackView'],
                supportsBarValueStacking: boolean,
                supportsResultCustomizationBy: boolean,
                resultCustomizationBy: trendsDataLogicValues['resultCustomizationBy'],
                showAnnotations: insightVizDataLogicValues['showAnnotations'],
                annotationsScope: insightVizDataLogicValues['annotationsScope'],
                pieChartVizOptions: trendsDataLogicValues['pieChartVizOptions']
            ): GeneralInput => ({
                hasLegend,
                usesInChartLegend,
                showLegend: !!showLegend,
                legendPosition,
                supportsValueOnSeries,
                showValuesOnSeries: !!showValuesOnSeries,
                showLabelOnSeries: !!showLabelOnSeries,
                supportsPercentStackView,
                showPercentStackView: !!showPercentStackView,
                supportsBarValueStacking,
                supportsResultCustomizationBy,
                resultCustomizationBy,
                showAnnotations,
                annotationsScope,
                pieTotalShown: !pieChartVizOptions?.hideAggregation,
            }),
        ],
        overlayInput: [
            (s) => [
                s.showMultipleYAxes,
                s.showAlertThresholdLines,
                s.mightContainFractionalNumbers,
                s.showConfidenceIntervals,
                s.confidenceLevel,
                s.showMovingAverage,
                s.movingAverageIntervals,
            ],
            (
                showMultipleYAxes: insightVizDataLogicValues['showMultipleYAxes'],
                showAlertThresholdLines: insightVizDataLogicValues['showAlertThresholdLines'],
                mightContainFractionalNumbers: boolean,
                showConfidenceIntervals: boolean,
                confidenceLevel: number,
                showMovingAverage: boolean,
                movingAverageIntervals: number
            ): OverlayInput => ({
                showMultipleYAxes: !!showMultipleYAxes,
                showAlertThresholdLines: !!showAlertThresholdLines,
                mightContainFractionalNumbers,
                showConfidenceIntervals,
                confidenceLevel,
                showMovingAverage,
                movingAverageIntervals,
            }),
        ],
        settingsInput: [
            (s) => [s.chartInput, s.generalInput, s.overlayInput],
            (chartInput: ChartInput, generalInput: GeneralInput, overlayInput: OverlayInput): ChartSettingsInput => ({
                ...chartInput,
                ...generalInput,
                ...overlayInput,
            }),
        ],
        groups: [
            (s) => [s.isTrends, s.settingsInput],
            (isTrends: boolean, settingsInput: ChartSettingsInput): ChartSettingsGroup[] =>
                isTrends ? buildChartSettingsGroups(settingsInput) : [],
        ],
        goalLinesSupported: [
            (s) => [s.isTrends, s.display],
            (isTrends: boolean, display: insightVizDataLogicValues['display']): boolean =>
                isTrends && supportsGoalLines(display),
        ],
        chartGoalLines: [
            (s) => [s.goalLines],
            (goalLines: insightVizDataLogicValues['goalLines']): GoalLine[] => goalLines ?? [],
        ],
    }),
    listeners(({ actions, values }) => ({
        changeTrendsFilter: ({ changes }) => {
            actions.updateQuerySource({ trendsFilter: { ...values.trendsFilter, ...changes } })
        },
        changeSetting: ({ id, value }) => {
            if (id === 'pie-total') {
                // A donut stores its options under the pie key too, so the setting holds when switching between them.
                actions.updateVizSpecificOptions({
                    [ChartDisplayType.ActionsPie]: { ...values.pieChartVizOptions, hideAggregation: !value },
                })
            } else {
                const changes = chartSettingPatch(id, value, values.settingsInput)
                if (changes) {
                    actions.changeTrendsFilter(changes)
                }
            }
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight chart setting changed', { setting: id, display: values.display ?? null })
        },
        addGoalLine: () => {
            actions.changeTrendsFilter({ goalLines: [...values.chartGoalLines, NEW_GOAL_LINE] })
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight chart setting changed', {
                setting: 'goal-line-added',
                display: values.display ?? null,
            })
        },
        changeGoalLine: ({ index, changes }) => {
            actions.changeTrendsFilter({
                goalLines: values.chartGoalLines.map((goalLine, goalLineIndex) =>
                    goalLineIndex === index ? { ...goalLine, ...changes } : goalLine
                ),
            })
        },
        removeGoalLine: ({ index }) => {
            actions.changeTrendsFilter({
                goalLines: values.chartGoalLines.filter((_, goalLineIndex) => goalLineIndex !== index),
            })
        },
    })),
])
