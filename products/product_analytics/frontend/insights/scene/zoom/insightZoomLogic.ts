import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import type { LogicWrapper } from 'kea'
import posthog from 'posthog-js'

import { dateRangeZoomEnd, insightVizDataLogic } from 'scenes/insights/insightVizDataLogic'
import type { QuerySourceUpdate, insightVizDataLogicType } from 'scenes/insights/insightVizDataLogic'
import { keyForInsightLogicProps } from 'scenes/insights/sharedUtils'

import type { DashboardFilter, DateRange } from '~/queries/schema/schema-general'
import type { InsightLogicProps, IntervalType } from '~/types'

export interface ZoomOrigin {
    dateRange: DateRange | null
    interval: IntervalType | null
    intervalManuallySet: boolean
    zoomedFrom: string
    zoomedTo: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightZoomLogicValues {
    dateRange: insightVizDataLogicType['values']['dateRange'] // insightVizDataLogic
    interval: insightVizDataLogicType['values']['interval'] // insightVizDataLogic
    isIntervalManuallySet: insightVizDataLogicType['values']['isIntervalManuallySet'] // insightVizDataLogic
    querySource: insightVizDataLogicType['values']['querySource'] // insightVizDataLogic
    canResetZoom: boolean
    zoomEnabled: boolean
    zoomOrigin: ZoomOrigin | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightZoomLogicActions {
    setIsIntervalManuallySet: (isIntervalManuallySet: boolean) => {
        isIntervalManuallySet: boolean
    } // insightVizDataLogic
    updateQuerySource: (querySource: QuerySourceUpdate) => {
        querySource: QuerySourceUpdate
    } // insightVizDataLogic
    zoomDateRange: (
        dateFrom: string,
        dateTo: string
    ) => {
        dateFrom: string
        dateTo: string
    } // insightVizDataLogic
    resetZoom: () => {
        value: true
    }
    setZoomOrigin: (origin: ZoomOrigin | null) => {
        origin: ZoomOrigin | null
    }
    zoomIn: (
        dateFrom: string,
        dateTo: string
    ) => {
        dateFrom: string
        dateTo: string
    }
}

export type insightZoomLogicType = MakeLogicType<insightZoomLogicValues, insightZoomLogicActions, InsightLogicProps>

export const insightZoomLogic: LogicWrapper<insightZoomLogicType> = kea<insightZoomLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'scene', 'zoom', 'insightZoomLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [insightVizDataLogic(props), ['querySource', 'dateRange', 'interval', 'isIntervalManuallySet']],
        actions: [insightVizDataLogic(props), ['zoomDateRange', 'updateQuerySource', 'setIsIntervalManuallySet']],
    })),
    actions({
        zoomIn: (dateFrom: string, dateTo: string) => ({ dateFrom, dateTo }),
        resetZoom: true,
        setZoomOrigin: (origin: ZoomOrigin | null) => ({ origin }),
    }),
    reducers({
        zoomOrigin: [
            null as ZoomOrigin | null,
            {
                setZoomOrigin: (_, { origin }) => origin,
            },
        ],
    }),
    selectors({
        zoomEnabled: [
            () => [(_, props) => props.filtersOverride],
            // A dashboard's dates win over the insight's, so a zoom would change nothing.
            (filtersOverride: DashboardFilter | null | undefined): boolean =>
                filtersOverride?.date_from == null && filtersOverride?.date_to == null,
        ],
        canResetZoom: [
            (s) => [s.zoomOrigin, s.dateRange],
            (zoomOrigin: ZoomOrigin | null, dateRange: DateRange | null | undefined): boolean =>
                !!zoomOrigin &&
                dateRange?.date_from === zoomOrigin.zoomedFrom &&
                dateRange?.date_to === zoomOrigin.zoomedTo,
        ],
    }),
    listeners(({ actions, values }) => ({
        zoomIn: ({ dateFrom, dateTo }) => {
            // A zoom inside a zoom still goes back to the dates from before the first one.
            const origin =
                values.canResetZoom && values.zoomOrigin
                    ? values.zoomOrigin
                    : {
                          dateRange: values.dateRange ?? null,
                          interval: values.interval ?? null,
                          intervalManuallySet: values.isIntervalManuallySet,
                      }
            actions.setZoomOrigin({
                ...origin,
                zoomedFrom: dateFrom,
                zoomedTo: dateRangeZoomEnd(dateTo, values.interval),
            })
            actions.zoomDateRange(dateFrom, dateTo)
        },
        resetZoom: () => {
            const origin = values.zoomOrigin
            if (!origin || !values.canResetZoom) {
                return
            }
            posthog.capture('insight zoom reset', { query_kind: values.querySource?.kind })
            actions.setZoomOrigin(null)
            const dateRange = origin.dateRange ?? undefined
            if (values.isIntervalManuallySet && !origin.intervalManuallySet) {
                actions.updateQuerySource({ dateRange } as QuerySourceUpdate)
                return
            }
            actions.updateQuerySource({ dateRange, interval: origin.interval ?? undefined } as QuerySourceUpdate)
            // An update with an interval counts as the user picking one, and here the user did not.
            actions.setIsIntervalManuallySet(origin.intervalManuallySet)
        },
    })),
])
