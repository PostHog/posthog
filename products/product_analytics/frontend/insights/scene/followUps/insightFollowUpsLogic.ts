import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, selectors } from 'kea'
import type { LogicWrapper } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { getCurrentTeamId } from 'lib/utils/getAppContext'
import { insightDataLogic } from 'scenes/insights/insightDataLogic'
import type { insightDataLogicValues } from 'scenes/insights/insightDataLogic'
import { insightLogic } from 'scenes/insights/insightLogic'
import type { insightLogicActions, insightLogicValues } from 'scenes/insights/insightLogic'
import { insightSceneLogic } from 'scenes/insights/insightSceneLogic'
import type { insightSceneLogicActions } from 'scenes/insights/insightSceneLogic'
import { keyForInsightLogicProps } from 'scenes/insights/sharedUtils'
import { urls } from 'scenes/urls'
import { userLogic } from 'scenes/userLogic'
import type { userLogicValues } from 'scenes/userLogic'

import { ItemMode } from '~/types'
import type { InsightLogicProps } from '~/types'

import { alertsList } from 'products/alerts/frontend/generated/api'
import type { AlertApi } from 'products/alerts/frontend/generated/api.schemas'
import { areAlertsSupportedForInsight } from 'products/alerts/frontend/logic/insightAlertsLogic'
import { subscriptionsList } from 'products/subscriptions/frontend/generated/api'
import type { SubscriptionApi } from 'products/subscriptions/frontend/generated/api.schemas'

import type { SentenceFollowUp, SentencePart } from '../sentence/buildSentence'
import { followUpLine, followUpsFrom } from './followUps'

export type FollowUpSlot = SentenceFollowUp['slot']

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightFollowUpsLogicValues {
    query: insightDataLogicValues['query'] // insightDataLogic
    insight: insightLogicValues['insight'] // insightLogic
    user: userLogicValues['user'] // userLogic
    alerts: AlertApi[]
    alertsLoading: boolean
    alertsSupported: boolean
    followUpLine: SentencePart[]
    followUps: SentenceFollowUp[]
    isSaved: boolean
    subscriptions: SubscriptionApi[]
    subscriptionsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightFollowUpsLogicActions {
    loadInsightSuccess: insightLogicActions['loadInsightSuccess'] // insightLogic
    saveInsightSuccess: insightLogicActions['saveInsightSuccess'] // insightLogic
    setSceneState: insightSceneLogicActions['setSceneState'] // insightSceneLogic
    loadAlerts: () => any
    loadAlertsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAlertsSuccess: (
        alerts: AlertApi[],
        payload?: any
    ) => {
        alerts: AlertApi[]
        payload?: any
    }
    loadSubscriptions: () => any
    loadSubscriptionsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSubscriptionsSuccess: (
        subscriptions: SubscriptionApi[],
        payload?: any
    ) => {
        subscriptions: SubscriptionApi[]
        payload?: any
    }
    openFollowUp: (
        slot: FollowUpSlot,
        itemId: string | null
    ) => {
        slot: FollowUpSlot
        itemId: string | null
    }
    startFollowUp: (slot: FollowUpSlot) => {
        slot: FollowUpSlot
    }
}

export type insightFollowUpsLogicType = MakeLogicType<
    insightFollowUpsLogicValues,
    insightFollowUpsLogicActions,
    InsightLogicProps
>

export const insightFollowUpsLogic: LogicWrapper<insightFollowUpsLogicType> = kea<insightFollowUpsLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'scene', 'followUps', 'insightFollowUpsLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [insightLogic(props), ['insight'], insightDataLogic(props), ['query'], userLogic, ['user']],
        actions: [
            insightLogic(props),
            ['loadInsightSuccess', 'saveInsightSuccess'],
            insightSceneLogic,
            ['setSceneState'],
        ],
    })),
    actions({
        openFollowUp: (slot: FollowUpSlot, itemId: string | null) => ({ slot, itemId }),
        startFollowUp: (slot: FollowUpSlot) => ({ slot }),
    }),
    loaders(({ values }) => ({
        subscriptions: [
            [] as SubscriptionApi[],
            {
                loadSubscriptions: async (_, breakpoint): Promise<SubscriptionApi[]> => {
                    const insightId = values.insight.id
                    if (!insightId) {
                        return []
                    }
                    const response = await subscriptionsList(String(getCurrentTeamId()), { insight: insightId })
                    breakpoint()
                    return response.results
                },
            },
        ],
        alerts: [
            [] as AlertApi[],
            {
                loadAlerts: async (_, breakpoint): Promise<AlertApi[]> => {
                    const insightId = values.insight.id
                    if (!insightId) {
                        return []
                    }
                    const response = await alertsList(String(getCurrentTeamId()), { insight_id: insightId })
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),
    selectors({
        isSaved: [
            (s) => [s.insight],
            (insight: insightLogicValues['insight']): boolean => !!insight.id && !!insight.short_id,
        ],
        alertsSupported: [
            (s) => [s.query],
            (query: insightDataLogicValues['query']): boolean => areAlertsSupportedForInsight(query),
        ],
        followUps: [
            (s) => [s.subscriptions, s.alerts, s.user],
            (subscriptions: SubscriptionApi[], alerts: AlertApi[], user: userLogicValues['user']): SentenceFollowUp[] =>
                followUpsFrom(subscriptions, alerts, user?.email),
        ],
        followUpLine: [
            (s) => [s.followUps],
            (followUps: SentenceFollowUp[]): SentencePart[] => followUpLine(followUps),
        ],
    }),
    listeners(({ actions, values }) => {
        const reload = (): void => {
            actions.loadSubscriptions()
            actions.loadAlerts()
        }
        return {
            loadInsightSuccess: reload,
            saveInsightSuccess: reload,
            // The editors for both are dialogs on their own URLs. Coming back to the insight means one may have changed.
            setSceneState: ({ insightMode }) => {
                if (insightMode === ItemMode.View) {
                    reload()
                }
            },
            openFollowUp: ({ slot, itemId }) => {
                const shortId = values.insight.short_id
                if (!shortId) {
                    return
                }
                if (slot === 'subscription') {
                    router.actions.push(
                        itemId ? urls.insightSubcription(shortId, itemId) : urls.insightSubcriptions(shortId)
                    )
                } else {
                    router.actions.push(itemId ? urls.insightAlert(shortId, itemId) : urls.insightAlerts(shortId))
                }
            },
            startFollowUp: ({ slot }) => {
                // pinned: analytics event name, renaming breaks dashboards
                posthog.capture('insight follow up started', { kind: slot })
                actions.openFollowUp(slot, 'new')
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadSubscriptions()
        actions.loadAlerts()
    }),
])
