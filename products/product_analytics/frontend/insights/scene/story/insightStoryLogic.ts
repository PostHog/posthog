export const insightStoryLogic: LogicWrapper<insightStoryLogicType> = kea<insightStoryLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'scene', 'story', 'insightStoryLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            insightDataChecksLogic(props),
            ['findings'],
            insightLogic(props),
            ['insight'],
            insightVizDataLogic(props),
            ['insightDataLoading', 'querySource'],
            insightZoomLogic(props),
            ['canResetZoom', 'zoomEnabled'],
            maxGlobalLogic,
            ['dataProcessingAccepted'],
            teamLogic,
            ['baseCurrency'],
            trendsDataLogic(props),
            [
                'display',
                'getTrendsHidden',
                'incompletenessOffsetFromEnd',
                'indexedResults',
                'interval',
                'isTrends',
                'trendsFilter',
            ],
        ],
        actions: [
            insightVizDataLogic(props),
            ['loadDataSuccess'],
            insightZoomLogic(props),
            ['resetZoom', 'zoomIn'],
            maxGlobalLogic,
            ['askSidePanelMax'],
        ],
    })),
    actions({
        openStory: true,
        closeStory: true,
        setActiveMoment: (momentId: string) => ({ momentId }),
        setPreviewMoment: (momentId: string | null) => ({ momentId }),
        stepMoment: (step: 1 | -1) => ({ step }),
        zoomToMoment: (momentId: string) => ({ momentId }),
        setZoomReturn: (zoomReturn: StoryZoomReturn | null) => ({ zoomReturn }),
        returnFromZoom: true,
        restoreChapter: (momentId: string) => ({ momentId }),
        sendMomentPrompt: (momentId: string, destination: StoryPromptDestination) => ({ momentId, destination }),
    }),
    loaders(({ values }) => ({
        evidenceResults: [
            null as EvidenceResults | null,
            {
                loadEvidence: async (_, breakpoint): Promise<EvidenceResults | null> => {
                    const queries = values.evidenceQueries
                    if (!queries) {
                        return null
                    }
                    const [breakdowns, people] = await Promise.all([
                        Promise.all(
                            queries.breakdowns.map(async ({ property, query }) => {
                                try {
                                    const response = await performQuery(query)
                                    return { property, query, rows: (response.results ?? []) as EvidenceRow[] }
                                } catch {
                                    return null
                                }
                            })
                        ),
                        queries.people
                            ? performQuery(queries.people)
                                  .then((response) => ({
                                      query: queries.people as NonNullable<EvidenceQueries['people']>,
                                      data: ((response.results?.[0] as EvidenceRow | undefined)?.data ??
                                          []) as number[],
                                  }))
                                  .catch(() => null)
                            : null,
                    ])
                    breakpoint()
                    return {
                        breakdowns: breakdowns.filter(
                            (breakdown): breakdown is NonNullable<typeof breakdown> => !!breakdown
                        ),
                        people,
                    }
                },
            },
        ],
        storyReadingRun: [
            null as StoryReadingRun | null,
            {
                loadStoryReadingRun: async (_, breakpoint): Promise<StoryReadingRun | null> => {
                    const series = values.storySeries
                    const facts = values.chapterFacts
                    if (!series || !facts.length || !values.dataProcessingAccepted) {
                        return null
                    }
                    let reading: InsightStoryApi | null = null
                    try {
                        reading = await insightsStoryCreate(String(getCurrentTeamId()), {
                            series_label: series.label.slice(0, 200) || 'Series',
                            insight_name: (values.insight.name || values.insight.derived_name || '').slice(0, 400),
                            chapters: facts.slice(0, 8).map(({ moment, evidence }) => ({
                                id: moment.id,
                                title: moment.title.slice(0, 200),
                                summary: plainStoryText(moment.summary).slice(0, 600),
                                // The model treats a data check as a note on quality, not as a cause.
                                evidence: evidence
                                    .slice(0, 6)
                                    .map((item) =>
                                        `${moment.kind === 'overview' ? 'Data check: ' : ''}${plainStoryText(item.text)}`.slice(
                                            0,
                                            600
                                        )
                                    ),
                            })),
                        })
                    } catch {
                        reading = null
                    }
                    breakpoint()
                    return reading ? { ok: true, reading } : { ok: false }
                },
            },
        ],
    })),
    reducers({
        // A reading belongs to the facts it was made from, and new evidence means new facts.
        storyReadingRun: {
            loadEvidence: () => null,
        },
        storyOpen: [
            false,
            {
                openStory: () => true,
                closeStory: () => false,
            },
        ],
        activeMomentId: [
            null as string | null,
            {
                setActiveMoment: (_, { momentId }) => momentId,
                restoreChapter: (_, { momentId }) => momentId,
                closeStory: () => null,
            },
        ],
        previewMomentId: [
            null as string | null,
            {
                setPreviewMoment: (_, { momentId }) => momentId,
                // The row under the pointer goes away with its page, and no pointer leave follows.
                setActiveMoment: () => null,
                closeStory: () => null,
            },
        ],
        zoomReturn: [
            null as StoryZoomReturn | null,
            {
                setZoomReturn: (_, { zoomReturn }) => zoomReturn,
            },
        ],
    }),
    selectors({
        formatValue: [
            (s) => [s.trendsFilter, s.baseCurrency],
            (trendsFilter: TrendsFilter | null | undefined, baseCurrency: teamLogicValues['baseCurrency']) =>
                (value: number): string =>
                    formatAggregationAxisValue(trendsFilter, value, baseCurrency),
        ],
        storySeries: [
            (s) => [s.indexedResults, s.getTrendsHidden, s.display, s.isTrends],
            (
                indexedResults: IndexedTrendResult[],
                getTrendsHidden: trendsDataLogicValues['getTrendsHidden'],
                display: ChartDisplayType | null | undefined,
                isTrends: boolean
            ): StorySeries | null => {
                if (!isTrends || (display && NON_TIME_SERIES_DISPLAY_TYPES.includes(display))) {
                    return null
                }
                const shown = (indexedResults ?? []).filter(
                    (result) => result.compare_label !== 'previous' && !getTrendsHidden(result) && !!result.days?.length
                )
                if (!shown.length) {
                    return null
                }
                const sum = (result: IndexedTrendResult): number =>
                    result.data.reduce((total, value) => total + value, 0)
                const lead = shown.reduce((best, result) => (sum(result) > sum(best) ? result : best))
                return {
                    key: String(lead.id),
                    label: lead.action?.custom_name || lead.label,
                    queryIndex: lead.action?.order ?? 0,
                    data: lead.data,
                    days: lead.days,
                    shownCount: shown.length,
                }
            },
        ],
        moments: [
            (s) => [s.storySeries, s.interval, s.incompletenessOffsetFromEnd, s.formatValue],
            (
                storySeries: StorySeries | null,
                interval: IntervalType | null | undefined,
                incompletenessOffsetFromEnd: number,
                formatValue: (value: number) => string
            ): ChartMoment[] =>
                storySeries
                    ? findChartMoments(storySeries, {
                          interval: interval ?? 'day',
                          incompletePoints: -incompletenessOffsetFromEnd,
                          formatValue,
                      })
                    : [],
        ],
        storyAvailable: [(s) => [s.moments], (moments: ChartMoment[]): boolean => moments.length > 0],
        evidenceQueries: [
            (s) => [s.querySource, s.storySeries],
            (
                querySource: insightVizDataLogicValues['querySource'],
                storySeries: StorySeries | null
            ): EvidenceQueries | null =>
                storySeries ? buildEvidenceQueries(querySource, storySeries.queryIndex) : null,
        ],
        evidenceStatus: [
            (s) => [s.evidenceQueries, s.evidenceResults, s.evidenceResultsLoading, s.insightDataLoading],
            (
                evidenceQueries: EvidenceQueries | null,
                evidenceResults: EvidenceResults | null,
                evidenceResultsLoading: boolean,
                insightDataLoading: boolean
            ): StoryEvidenceStatus => {
                if (!evidenceQueries) {
                    return 'unavailable'
                }
                return evidenceResultsLoading || insightDataLoading || !evidenceResults ? 'loading' : 'ready'
            },
        ],
        chapterFacts: [
            (s) => [
                s.moments,
                s.storySeries,
                s.evidenceResults,
                s.evidenceStatus,
                s.findings,
                s.interval,
                s.incompletenessOffsetFromEnd,
                s.formatValue,
            ],
            (
                moments: ChartMoment[],
                storySeries: StorySeries | null,
                evidenceResults: EvidenceResults | null,
                evidenceStatus: StoryEvidenceStatus,
                findings: DataCheck[],
                interval: IntervalType | null | undefined,
                incompletenessOffsetFromEnd: number,
                formatValue: (value: number) => string
            ): StoryChapterFacts[] =>
                moments.map((moment) => {
                    if (moment.kind === 'overview') {
                        return {
                            moment,
                            hasCause: false,
                            evidence: findings.map((check) => ({
                                id: `check-${check.key}`,
                                text: `${check.result}.`,
                                query: null,
                                driverShare: null,
                            })),
                        }
                    }
                    return {
                        moment,
                        hasCause: evidenceStatus !== 'unavailable' && ['peak', 'dip', 'shift'].includes(moment.kind),
                        evidence:
                            storySeries && evidenceResults && evidenceStatus === 'ready'
                                ? evidenceForMoment(moment, evidenceResults, {
                                      values: storySeries.data,
                                      completePoints: storySeries.data.length + incompletenessOffsetFromEnd,
                                      interval: interval ?? 'day',
                                      formatValue,
                                  })
                                : [],
                    }
                }),
        ],
        readingStatus: [
            (s) => [s.dataProcessingAccepted, s.storyReadingRun, s.storyReadingRunLoading, s.evidenceStatus],
            (
                dataProcessingAccepted: boolean,
                storyReadingRun: StoryReadingRun | null,
                storyReadingRunLoading: boolean,
                evidenceStatus: StoryEvidenceStatus
            ): StoryReadingStatus => {
                if (!dataProcessingAccepted) {
                    return 'unavailable'
                }
                if (storyReadingRunLoading || evidenceStatus === 'loading' || !storyReadingRun) {
                    return 'loading'
                }
                return storyReadingRun.ok ? 'ready' : 'failed'
            },
        ],
        headline: [
            (s) => [s.storyReadingRun],
            (storyReadingRun: StoryReadingRun | null): string | null => {
                const headline = storyReadingRun?.ok ? storyReadingRun.reading.headline.trim() : ''
                // The model sometimes leaves the full stop off.
                return headline ? (/[.!?]$/.test(headline) ? headline : `${headline}.`) : null
            },
        ],
        chapters: [
            (s) => [s.chapterFacts, s.storyReadingRun],
            (chapterFacts: StoryChapterFacts[], storyReadingRun: StoryReadingRun | null): StoryChapter[] =>
                chapterFacts.map((facts) => {
                    const read = storyReadingRun?.ok
                        ? storyReadingRun.reading.chapters.find((chapter) => chapter.id === facts.moment.id)
                        : undefined
                    return {
                        ...facts,
                        reading:
                            read?.reading && facts.evidence.length
                                ? { text: read.reading, confidence: confidenceOf(facts.evidence) }
                                : null,
                    }
                }),
        ],
        // A date range picked by hand after the zoom means there is no zoom to come back from.
        zoomReturnTarget: [
            (s) => [s.zoomReturn, s.canResetZoom],
            (zoomReturn: StoryZoomReturn | null, canResetZoom: boolean): StoryZoomReturn | null =>
                canResetZoom ? zoomReturn : null,
        ],
        activeIndex: [
            (s) => [s.chapters, s.activeMomentId],
            (chapters: StoryChapter[], activeMomentId: string | null): number =>
                Math.max(
                    chapters.findIndex((chapter) => chapter.moment.id === activeMomentId),
                    0
                ),
        ],
        activeChapter: [
            (s) => [s.chapters, s.activeIndex],
            (chapters: StoryChapter[], activeIndex: number): StoryChapter | null => chapters[activeIndex] ?? null,
        ],
        highlightedChapter: [
            (s) => [s.chapters, s.previewMomentId, s.activeChapter],
            (
                chapters: StoryChapter[],
                previewMomentId: string | null,
                activeChapter: StoryChapter | null
            ): StoryChapter | null =>
                chapters.find((chapter) => chapter.moment.id === previewMomentId) ?? activeChapter,
        ],
    }),
    listeners(({ actions, values }) => ({
        openStory: () => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight story opened', {
                moments: values.moments.map((moment) => moment.kind),
                can_search_for_cause: !!values.evidenceQueries,
            })
            actions.loadEvidence()
        },
        loadDataSuccess: () => {
            if (values.storyOpen) {
                actions.loadEvidence()
            }
        },
        loadEvidenceSuccess: () => {
            if (values.storyOpen) {
                actions.loadStoryReadingRun()
            }
        },
        setActiveMoment: ({ momentId }) => {
            const position = values.chapters.findIndex((chapter) => chapter.moment.id === momentId)
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight story chapter viewed', {
                moment: values.chapters[position]?.moment.kind,
                position: position + 1,
                chapters: values.chapters.length,
            })
        },
        closeStory: () => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight story closed', { chapters: values.chapters.length })
        },
        stepMoment: ({ step }) => {
            const next = values.chapters[values.activeIndex + step]
            if (next) {
                actions.setActiveMoment(next.moment.id)
            }
        },
        zoomToMoment: ({ momentId }) => {
            const moment = values.moments.find((candidate) => candidate.id === momentId)
            const days = values.storySeries?.days
            if (!moment?.ranges.length || !days) {
                return
            }
            const first = Math.max(moment.ranges[0][0] - ZOOM_PADDING, 0)
            const last = Math.min(moment.ranges[moment.ranges.length - 1][1] + ZOOM_PADDING, days.length - 1)
            // A zoom inside a zoom still goes back to the chapter of the first one.
            if (!values.zoomReturnTarget) {
                actions.setZoomReturn({ momentId, title: moment.title, position: values.activeIndex + 1 })
            }
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight story zoomed', { moment: moment.kind })
            actions.zoomIn(days[first], days[last])
        },
        returnFromZoom: () => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight story zoom returned')
            actions.resetZoom()
        },
        // The chart's own reset button ends the zoom too, so the chapter comes back whichever one is used.
        resetZoom: () => {
            if (values.zoomReturn) {
                actions.restoreChapter(values.zoomReturn.momentId)
                actions.setZoomReturn(null)
            }
        },
        sendMomentPrompt: ({ momentId, destination }) => {
            const chapter = values.chapters.find((candidate) => candidate.moment.id === momentId)
            if (!chapter || !values.storySeries) {
                return
            }
            const shortId = values.insight.short_id
            const prompt = momentPrompt(chapter.moment, chapter.evidence, {
                insightUrl: shortId ? urls.absolute(urls.currentProject(urls.insightView(shortId))) : null,
                // JSON has no raw line breaks, so a name inside the query cannot add lines to the prompt.
                query: values.querySource ? JSON.stringify(values.querySource) : null,
                seriesLabel: values.storySeries.label,
                interval: values.interval ?? 'day',
            })
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight story prompt sent', { moment: chapter.moment.kind, destination })
            if (destination === 'posthog_ai') {
                actions.askSidePanelMax(prompt)
            } else {
                void copyToClipboard(prompt, 'prompt for your agent')
            }
        },
    })),
])
