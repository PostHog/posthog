export interface StorySeries {
    key: string
    label: string
    queryIndex: number
    data: number[]
    days: string[]
    shownCount: number
}

export type StoryEvidenceStatus = 'unavailable' | 'loading' | 'ready'

export interface StoryChapterFacts {
    moment: ChartMoment
    evidence: MomentEvidence[]
    hasCause: boolean
}

/** How far the evidence carries the likely cause. It is worked out from the findings, not asked of the model. */
export type StoryConfidence = 'high' | 'medium' | 'guess'

export interface StoryReading {
    text: string
    confidence: StoryConfidence
}

export interface StoryChapter extends StoryChapterFacts {
    reading: StoryReading | null
}

/** A failed reading is kept as a value, so the story can say so and keep its facts. */
export type StoryReadingRun = { ok: true; reading: InsightStoryApi } | { ok: false }

export type StoryReadingStatus = 'unavailable' | 'loading' | 'ready' | 'failed'

export type StoryPromptDestination = 'posthog_ai' | 'clipboard'

export interface StoryZoomReturn {
    momentId: string
    title: string
    position: number
}

const HIGH_CONFIDENCE_SHARE = 0.8

function confidenceOf(evidence: MomentEvidence[]): StoryConfidence {
    const shares = evidence.map((item) => item.driverShare).filter((share): share is number => share !== null)
    if (!shares.length) {
        return 'guess'
    }
    return Math.max(...shares) >= HIGH_CONFIDENCE_SHARE ? 'high' : 'medium'
}

