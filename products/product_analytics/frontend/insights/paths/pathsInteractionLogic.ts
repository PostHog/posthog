export type pathsInteractionLogicType = MakeLogicType<
    pathsInteractionLogicValues,
    pathsInteractionLogicActions,
    InsightLogicProps,
    pathsInteractionLogicMeta
>

export const pathsInteractionLogic = kea<pathsInteractionLogicType>([
    path((key) => ['scenes', 'paths', 'pathsInteractionLogic', key]),
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps(DEFAULT_KEY)),

    actions({
        setNodes: (nodes: PathNodeData[], canvasHeight: number) => ({ nodes, canvasHeight }),
        hoverNode: (nodeIndex: number) => ({ nodeIndex }),
        hoverLink: (sourceIndex: number, targetIndex: number, linkIndex: number) => ({
            sourceIndex,
            targetIndex,
            linkIndex,
        }),
        requestClearHover: true,
        clearHover: true,
        hoverCard: (nodeIndex: number) => ({ nodeIndex }),
        unhoverCard: true,
    }),

    reducers({
        nodes: [
            [] as PathNodeData[],
            {
                setNodes: (_, { nodes }) => nodes,
            },
        ],
        canvasHeight: [
            0 as number,
            {
                setNodes: (_, { canvasHeight }) => canvasHeight,
            },
        ],
        hoverTarget: [
            null as HoverTarget | null,
            {
                hoverNode: (_, { nodeIndex }) => ({ type: 'node', nodeIndex }),
                hoverCard: (_, { nodeIndex }) => ({ type: 'node', nodeIndex }),
                hoverLink: (_, { sourceIndex, targetIndex, linkIndex }) => ({
                    type: 'link',
                    sourceIndex,
                    targetIndex,
                    linkIndex,
                }),
                clearHover: () => null,
                setNodes: () => null,
            },
        ],
        cardHovered: [
            false,
            {
                hoverCard: () => true,
                // Leaving a card re-enables the SVG handlers right away. If the pointer lands on
                // an SVG element within the debounce window, its handler starts a new hover and
                // cancels the pending clear, so the card to SVG transition stays seamless.
                unhoverCard: () => false,
                clearHover: () => false,
                setNodes: () => false,
            },
        ],
        // The card whose popover is open. Debounced through clearHover, so that crossing the
        // seam between a card and its own popover does not close the popover.
        cardPopoverIndex: [
            null as number | null,
            {
                hoverCard: (_, { nodeIndex }) => nodeIndex,
                hoverNode: () => null,
                hoverLink: () => null,
                clearHover: () => null,
                setNodes: () => null,
            },
        ],
    }),

    listeners(({ actions, cache }) => ({
        requestClearHover: () => {
            // Same key, so a new request replaces the pending one. This is a one-shot, so it
            // deregisters itself once it fires: the plugin re-runs the setup of every entry that
            // is still registered when the tab becomes visible, which would otherwise re-arm this
            // timer on every return to the tab for the rest of the logic's life.
            // `pauseOnPageHidden` is off because a 30 ms pointer debounce is not background work,
            // and pausing it holds a pending clear until the tab is visible again.
            cache.disposables.add(
                () => {
                    const timer = setTimeout(() => {
                        cache.disposables.dispose(CLEAR_HOVER_TIMER)
                        actions.clearHover()
                    }, CLEAR_HOVER_DEBOUNCE_MS)
                    return () => clearTimeout(timer)
                },
                CLEAR_HOVER_TIMER,
                { pauseOnPageHidden: false }
            )
        },
        hoverNode: () => {
            cache.disposables.dispose(CLEAR_HOVER_TIMER)
        },
        hoverLink: () => {
            cache.disposables.dispose(CLEAR_HOVER_TIMER)
        },
        hoverCard: () => {
            cache.disposables.dispose(CLEAR_HOVER_TIMER)
        },
        unhoverCard: () => {
            actions.requestClearHover()
        },
    })),

    selectors({
        activeIndices: [
            (s) => [s.hoverTarget, s.nodes],
            (
                hoverTarget: HoverTarget | null,
                nodes: PathNodeData[]
            ): { nodeIndices: Set<number>; linkIndices: Set<number> } => {
                const empty = { nodeIndices: new Set<number>(), linkIndices: new Set<number>() }
                if (!hoverTarget || nodes.length === 0) {
                    return empty
                }

                if (hoverTarget.type === 'node') {
                    const node = nodes.find((n) => n.index === hoverTarget.nodeIndex)
                    if (!node) {
                        return empty
                    }
                    const forward = getForwardConnectedIndices(node)
                    for (const link of node.targetLinks) {
                        forward.linkIndices.add(link.index)
                        forward.nodeIndices.add(link.source.index)
                    }
                    return forward
                }

                const source = nodes.find((n) => n.index === hoverTarget.sourceIndex)
                const target = nodes.find((n) => n.index === hoverTarget.targetIndex)
                if (!source || !target) {
                    return empty
                }
                const forward = getForwardConnectedIndices(target)
                forward.nodeIndices.add(source.index)
                forward.linkIndices.add(hoverTarget.linkIndex)
                return forward
            },
        ],
        cardTops: [
            (s) => [s.nodes, s.canvasHeight],
            (nodes: PathNodeData[], canvasHeight: number): Map<number, number> =>
                resolveCardOverlaps(nodes, canvasHeight),
        ],
        resolvedNodeCards: [
            (s) => [s.nodes, s.activeIndices, s.cardTops],
            (
                nodes: PathNodeData[],
                activeIndices: { nodeIndices: Set<number>; linkIndices: Set<number> },
                cardTops: Map<number, number>
            ): PathNodeData[] => {
                const withState =
                    activeIndices.nodeIndices.size > 0
                        ? activateNodes(nodes, activeIndices.nodeIndices)
                        : deactivateNodes(nodes)
                return withState.map((node) =>
                    cardTops.has(node.index) ? { ...node, resolvedTop: cardTops.get(node.index) } : node
                )
            },
        ],
    }),
])
