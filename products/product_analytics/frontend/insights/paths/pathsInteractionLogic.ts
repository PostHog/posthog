import { MakeLogicType, actions, kea, key, listeners, path, props, reducers, selectors } from 'kea'

import { keyForInsightLogicProps } from 'scenes/insights/sharedUtils'

import { InsightLogicProps } from '~/types'

import {
    PathNodeData,
    activateNodes,
    deactivateNodes,
    getForwardConnectedIndices,
    resolveCardOverlaps,
} from './pathUtils'

export type HoverTarget =
    | { type: 'node'; nodeIndex: number }
    | { type: 'link'; sourceIndex: number; targetIndex: number; linkIndex: number }

const DEFAULT_KEY = 'default_paths_interaction_key'
const CLEAR_HOVER_DEBOUNCE_MS = 30
const CLEAR_HOVER_TIMER = 'clearHoverTimer'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pathsInteractionLogicValues {
    activeIndices: {
        linkIndices: Set<number>
        nodeIndices: Set<number>
    }
    canvasHeight: number
    cardHovered: boolean
    cardPopoverIndex: number | null
    cardTops: Map<number, number>
    hoverTarget: HoverTarget | null
    nodes: PathNodeData[]
    resolvedNodeCards: PathNodeData[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pathsInteractionLogicActions {
    clearHover: () => {
        value: true
    }
    hoverCard: (nodeIndex: number) => {
        nodeIndex: number
    }
    hoverLink: (
        sourceIndex: number,
        targetIndex: number,
        linkIndex: number
    ) => {
        linkIndex: number
        sourceIndex: number
        targetIndex: number
    }
    hoverNode: (nodeIndex: number) => {
        nodeIndex: number
    }
    requestClearHover: () => {
        value: true
    }
    setNodes: (
        nodes: PathNodeData[],
        canvasHeight: number
    ) => {
        canvasHeight: number
        nodes: PathNodeData[]
    }
    unhoverCard: () => {
        value: true
    }
}

