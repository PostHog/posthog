export enum AggregationType {
    Total = 'total',
    Average = 'average',
    Median = 'median',
}

export function getAggregatedValue(
    item: IndexedTrendResult,
    aggregation: `${AggregationType}`,
    isNonTimeSeriesDisplay: boolean
): number | undefined {
    if (aggregation === 'total' || isNonTimeSeriesDisplay) {
        let value = item.count ?? item.aggregated_value
        if (item.aggregated_value > item.count || (item.aggregated_value < 0 && item.aggregated_value < item.count)) {
            value = item.aggregated_value
        }
        return value
    } else if (aggregation === 'average') {
        return average(item.data)
    } else if (aggregation === 'median') {
        return median(item.data)
    }
    return undefined
}

export function compareResultKey(item: IndexedTrendResult): string {
    return JSON.stringify([getResultOrder(item), item.label ?? '', item.breakdown_value ?? ''])
}

// Each event lands in exactly one breakdown value. Unique counts don't: one person can be in several rows.
const DAY_ADDITIVE_MATHS = new Set<string>([
    'total',
    'sum',
    'first_time_for_user',
    'first_matching_event_for_user',
    'first_time_for_group',
    'first_matching_event_for_group',
])

// Cohorts overlap, and a hidden "Other" bucket drops part of the whole from the results.
function breakdownSplitsAWhole(breakdownFilter: BreakdownFilter | null | undefined): boolean {
    return (
        hasBreakdownFilter(breakdownFilter) &&
        breakdownFilter.breakdown_type !== 'cohort' &&
        !breakdownFilter.breakdown_hide_other_aggregation
    )
}

// The query sums once per session and breakdown value, so a session lands in every value it touched.
function isSessionPropertySum(entity: EntityNode): boolean {
    return (
        entity.math === 'sum' &&
        (entity.math_property === '$session_duration' || entity.math_property_type === 'session_properties')
    )
}

// One person can count under several breakdown values, so these need their own distinct daily totals.
const UNIQUE_COUNT_MATHS = new Set<string>(['dau', 'weekly_active', 'monthly_active', 'unique_session', 'unique_group'])

function percentOfTotalGroupKey(item: ResultSeriesRow & Pick<TrendResult, 'compare_label'>): string {
    return JSON.stringify([getResultOrder(item), item.compare_label ?? ''])
}

function isOtherBreakdownValue(breakdownValue: IndexedTrendResult['breakdown_value']): boolean {
    return Array.isArray(breakdownValue) ? breakdownValue.some(isOtherBreakdown) : isOtherBreakdown(breakdownValue)
}

export interface UniqueDayTotals {
    query: TrendsQuery
    // `order` is the series' position in `query`, not in the insight.
    rows: { order: number; compare_label: TrendResult['compare_label']; days: string[]; data: number[] }[]
}

function isSameTotalsQuery(a: TrendsQuery | null | undefined, b: TrendsQuery | null): boolean {
    return !!a && !!b && compareDataNodeQuery(a, b, { ignoreVisualizationOnlyChanges: true })
}

