export type trendsAxisSettingsLogicType = MakeLogicType<
    trendsAxisSettingsLogicValues,
    trendsAxisSettingsLogicActions,
    InsightLogicProps,
    trendsAxisSettingsLogicMeta
>

export const trendsAxisSettingsLogic = kea<trendsAxisSettingsLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('trendsAxisSettingsLogic')),
    path((key) => ['products', 'product_analytics', 'insights', 'trends', 'trendsAxisSettingsLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            insightLogic(props),
            ['canEditInsight', 'hasOverrides'],
            trendsDataLogic(props),
            ['indexedResults', 'resultCustomizationBy', 'resultCustomizations', 'querySource'],
        ],
        actions: [insightVizDataLogic(props), ['updateInsightFilter']],
    })),
    actions({
        openModal: (axis: TrendsAxisPosition, series: RenderedTrendsAxisSeries[]) => ({ axis, series }),
        closeModal: true,
        selectAxis: (axis: TrendsAxisPosition) => ({ axis }),
        setEntries: (entries: TrendsAxisEntry[]) => ({ entries }),
        setSeriesPosition: (key: string, position: TrendsAxisPosition) => ({ key, position }),
        save: true,
        resetAxes: true,
    }),
    reducers({
        axis: [
            null as TrendsAxisPosition | null,
            {
                openModal: (_, { axis }) => axis,
                selectAxis: (_, { axis }) => axis,
                closeModal: () => null,
            },
        ],
        entries: [
            [] as TrendsAxisEntry[],
            {
                setEntries: (_, { entries }) => entries,
                setSeriesPosition: (entries, { key, position }) =>
                    entries.map((entry) => (entry.key === key ? { ...entry, position } : entry)),
                closeModal: () => [],
            },
        ],
        hasChanges: [false, { openModal: () => false, setSeriesPosition: () => true, closeModal: () => false }],
    }),
    listeners(({ actions, values }) => ({
        openModal: ({ axis, series }) => {
            const entries = new Map<string, TrendsAxisEntry>()
            for (const result of values.indexedResults ?? []) {
                const rendered = series.find((item) => item.id === String(result.id))
                const key = getTrendResultCustomizationKey(values.resultCustomizationBy, result, values.querySource)
                // Comparison periods share a customization key and must move together.
                if (rendered && !entries.has(key)) {
                    const savedPosition = getTrendResultCustomization(
                        values.resultCustomizationBy,
                        result,
                        values.resultCustomizations,
                        values.querySource
                    )?.yAxisPosition
                    entries.set(key, {
                        key,
                        label: rendered.label,
                        position:
                            savedPosition === 'left' || savedPosition === 'right' ? savedPosition : rendered.position,
                    })
                }
            }
            actions.setEntries([...entries.values()])
            posthog.capture('insight axis settings opened', { axis })
        },
        save: () => {
            if (!values.canEditInsight || values.hasOverrides) {
                return
            }
            if (values.hasChanges) {
                const resultCustomizations: Record<string, ResultCustomizationByValue | ResultCustomizationByPosition> =
                    {
                        ...values.resultCustomizations,
                    }
                for (const entry of values.entries) {
                    resultCustomizations[entry.key] = {
                        ...resultCustomizations[entry.key],
                        assignmentBy: values.resultCustomizationBy,
                        yAxisPosition: entry.position,
                    }
                }
                actions.updateInsightFilter({ resultCustomizations } as Partial<TrendsFilter>)
            }
            posthog.capture('insight axis settings saved', { axis: values.axis, changed: values.hasChanges })
            actions.closeModal()
        },
        resetAxes: () => {
            if (!values.canEditInsight || values.hasOverrides) {
                return
            }
            actions.updateInsightFilter({
                resultCustomizations: Object.fromEntries(
                    Object.entries(values.resultCustomizations ?? {}).map(([key, customization]) => [
                        key,
                        { ...customization, yAxisPosition: 'auto' as const },
                    ])
                ),
            })
            posthog.capture('insight axis settings reset', { axis: values.axis })
            actions.closeModal()
        },
    })),
])
