export type TrendsAxisPosition = 'left' | 'right'

export interface RenderedTrendsAxisSeries {
    id: string
    label: string
    position: TrendsAxisPosition
}

export interface TrendsAxisEntry {
    key: string
    label: string
    position: TrendsAxisPosition
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
