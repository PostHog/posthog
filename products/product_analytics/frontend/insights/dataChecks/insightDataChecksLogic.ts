const FORCED_REFRESHES: (RefreshType | undefined)[] = ['force_async', 'force_blocking']
// The checks run up to four queries of 20 seconds each, after a wait for server slots.
const DATA_CHECKS_TIMEOUT_MS = 120_000
const LABEL_OPEN_MS = 2500
const YIELDED_TO_CHART = 'yielded to chart'
export const insightDataChecksLogic: LogicWrapper<insightDataChecksLogicType> = kea<insightDataChecksLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'dataChecks', 'insightDataChecksLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            insightDataLogic(props),
            ['query'],
            insightVizDataLogic(props),
            ['insightDataLoading', 'querySource'],
            insightLogic(props),
            ['hasOverrides'],
            featureFlagLogic,
            ['featureFlags'],
            teamLogic,
            ['currentTeam', 'currentTeamLoading'],
            sidePanelStateLogic,
            ['sidePanelOpen', 'selectedTab'],
        ],
        actions: [
            insightVizDataLogic(props),
            ['loadData', 'loadDataSuccess', 'updateQuerySource'],
            featureFlagLogic,
            ['setFeatureFlags'],
            sidePanelStateLogic,
            ['openSidePanel'],
            teamLogic,
            ['updateCurrentTeam', 'updateCurrentTeamSuccess'],
        ],
    })),
    actions({
        addFilterRule: (check: InsightDataCheckApi) => ({ check }),
        checkData: (again: boolean = false) => ({ again }),
        closeLabel: true,
        setFiltersTestAccounts: (filtersTestAccounts: boolean, check: InsightDataCheckKeyEnumApi) => ({
            filtersTestAccounts,
            check,
        }),
        fixWithPostHogAI: (check: InsightDataCheckApi) => ({ check }),
        excludeFromInsight: (check: InsightDataCheckApi) => ({ check }),
        reportButtonClicked: (button: DataChecksButton, check: InsightDataCheckKeyEnumApi | null = null) => ({
            button,
            check,
        }),
        reportCheckExpanded: (check: InsightDataCheckApi) => ({ check }),
        reportDataChecksViewed: true,
    }),
    loaders(({ cache }) => ({
        dataChecksRun: [
            null as DataChecksRun | null,
            {
                loadDataChecks: async (query: DataChecksQuery): Promise<DataChecksRun | null> => {
                    // Leaving the insight cancels the run, queued or running, so it does not hold the chart queue.
                    // A hidden tab keeps it, because a person comes back to the result.
                    const abortController = new AbortController()
                    const clientQueryId = uuid()
                    let sent = false
                    cache.dataChecksAbortController = abortController
                    cache.disposables.add(() => () => abortController.abort(), 'dataChecksRun', {
                        pauseOnPageHidden: false,
                    })
                    try {
                        // The checks hold the same server slots as charts, so they wait behind the charts in the queue.
                        const result = await concurrencyController.run({
                            debugTag: 'InsightDataChecks',
                            abortController,
                            fn: async () => {
                                // A stalled request would block every later run, which waits for this one to end.
                                const timeout = setTimeout(() => abortController.abort(), DATA_CHECKS_TIMEOUT_MS)
                                sent = true
                                try {
                                    return await insightsDataChecksCreate(
                                        String(getCurrentTeamId()),
                                        {
                                            query,
                                            client_query_id: clientQueryId,
                                        } as unknown as InsightDataChecksRequestApi,
                                        undefined,
                                        { signal: abortController.signal }
                                    )
                                } finally {
                                    clearTimeout(timeout)
                                }
                            },
                        })
                        return { ok: true, result }
                    } catch (error) {
                        // An aborted request does not stop the queries the server runs for it, and they hold its slots.
                        if (sent && abortController.signal.aborted) {
                            void cancelQueryOnServer(getCurrentTeamId(), clientQueryId)
                        }
                        if (abortController.signal.reason === YIELDED_TO_CHART) {
                            return null
                        }
                        return { ok: false, denied: error instanceof ApiError && error.status === 403 }
                    }
                },
            },
        ],
    })),
    reducers({
        requestedQuery: [
            null as DataChecksQuery | null,
            {
                loadDataChecks: (_, query) => query,
            },
        ],
        // A person can refresh the chart during a run. That run is for the events as they were before.
        checkAgainRequested: [
            false,
            {
                checkData: (requested, { again }) => requested || again,
                loadDataChecks: () => false,
            },
        ],
        labelHeldOpen: [
            false,
            {
                loadDataChecksSuccess: () => true,
                closeLabel: () => false,
            },
        ],
        // Shown while the checks run again, so the list keeps its place and its open rows.
        lastResult: [
            null as InsightDataChecksApi | null,
            {
                loadDataChecksSuccess: (lastResult, { dataChecksRun }) =>
                    dataChecksRun?.ok ? dataChecksRun.result : lastResult,
            },
        ],
    }),
    selectors({
        postHogAIOpen: [
            (s) => [s.sidePanelOpen, s.selectedTab],
            (sidePanelOpen: boolean, selectedTab: SidePanelTab | null): boolean =>
                sidePanelOpen && selectedTab === SidePanelTab.Max,
        ],
        filterRemovesBots: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): boolean =>
                removesBotTraffic(currentTeam?.test_account_filters ?? []),
        ],
        // The server only checks insights whose series are all events, so no request goes out for the rest.
        // Compared by value, so a render that rebuilds the same query is not a new query.
        checkedQuery: [
            (s) => [s.query, s.featureFlags, s.hasOverrides],
            (query: Node | null, featureFlags: FeatureFlagsSet, hasOverrides: boolean): DataChecksQuery | null => {
                // The server applies a chart's overrides, so the page does not hold the query the chart runs.
                if (!featureFlags[FEATURE_FLAGS.INSIGHT_DATA_CHECKS] || !isInsightVizNode(query) || hasOverrides) {
                    return null
                }
                const source = query.source
                if (!isInsightQueryWithSeries(source) || !source.series.length || !source.series.every(isEventsNode)) {
                    return null
                }
                return { kind: NodeKind.InsightVizNode, source }
            },
            { resultEqualityCheck: objectsEqual },
        ],
        status: [
            (s) => [s.checkedQuery, s.requestedQuery, s.dataChecksRunLoading, s.dataChecksRun],
            (
                checkedQuery: DataChecksQuery | null,
                requestedQuery: DataChecksQuery | null,
                dataChecksRunLoading: boolean,
                dataChecksRun: DataChecksRun | null
            ): InsightDataChecksStatus => {
                if (!checkedQuery) {
                    return 'unavailable'
                }
                // The checks run after the chart loads, so the last run is out of date from the moment the query changes.
                if (dataChecksRunLoading || !dataChecksRun || requestedQuery !== checkedQuery) {
                    return 'checking'
                }
                return statusOfRun(dataChecksRun)
            },
        ],
        result: [
            (s) => [s.dataChecksRun, s.status],
            (dataChecksRun: DataChecksRun | null, status: InsightDataChecksStatus): InsightDataChecksApi | null =>
                dataChecksRun?.ok && status !== 'checking' ? dataChecksRun.result : null,
        ],
        filtersTestAccounts: [
            (s) => [s.lastResult],
            (lastResult: InsightDataChecksApi | null): boolean => lastResult?.coverage?.filters_test_accounts ?? false,
        ],
        visibleChecks: [
            (s) => [s.status, s.lastResult, s.checks],
            (
                status: InsightDataChecksStatus,
                lastResult: InsightDataChecksApi | null,
                checks: InsightDataCheckApi[]
            ): InsightDataCheckApi[] => (status === 'checking' ? (lastResult?.checks ?? []) : checks),
        ],
        // The chart's own toggle, which changes before the checks run again.
        queryFiltersTestAccounts: [
            (s) => [s.checkedQuery],
            (checkedQuery: DataChecksQuery | null): boolean => !!checkedQuery?.source.filterTestAccounts,
        ],
        checks: [
            (s) => [s.result],
            (result: InsightDataChecksApi | null): InsightDataCheckApi[] => result?.checks ?? [],
        ],
        findings: [
            (s) => [s.checks],
            (checks: InsightDataCheckApi[]): InsightDataCheckApi[] => checks.filter(isFinding),
        ],
        labelOpen: [
            (s) => [s.status, s.labelHeldOpen],
            // A finding keeps its label, because the icon alone does not say what the person needs to look at.
            (status: InsightDataChecksStatus, labelHeldOpen: boolean): boolean =>
                status === 'checking' || status === 'warning' || status === 'problem' || labelHeldOpen,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        // The chart can load more than once for one query, and the answer for that query is already on its way.
        // One run at a time: a run for an older query keeps its queries on the server until it ends.
        checkData: () => {
            const query = values.checkedQuery
            const isWanted = values.checkAgainRequested || query !== values.requestedQuery
            if (query && isWanted && !values.dataChecksRunLoading) {
                actions.loadDataChecks(query)
            }
        },
        loadDataChecks: () => {
            cache.dataChecksStartedAt = performance.now()
            posthog.capture('insight data checks loading')
        },
        // The query can change during a run. The chart for the new query can finish before that run does.
        loadDataChecksSuccess: async ({ dataChecksRun }, breakpoint) => {
            posthog.capture('insight data checks loaded', {
                // A run with no result gave its slot to the chart, which checks again after it loads.
                status: dataChecksRun ? statusOfRun(dataChecksRun) : 'cancelled',
                duration_ms: Math.round(performance.now() - cache.dataChecksStartedAt),
                findings: dataChecksRun?.ok
                    ? dataChecksRun.result.checks.filter(isFinding).map((check) => check.key)
                    : [],
            })
            if (!values.insightDataLoading) {
                actions.checkData()
            }
            await breakpoint(LABEL_OPEN_MS)
            actions.closeLabel()
        },
        // The flags can arrive after the chart has loaded.
        setFeatureFlags: () => {
            if (!values.insightDataLoading) {
                actions.checkData()
            }
        },
        // The queue has one slot, so a check in flight would hold back the chart. The check runs again after the chart.
        loadData: ({ pollOnly }) => {
            if (!pollOnly && values.dataChecksRunLoading) {
                actions.checkData(true)
                cache.dataChecksAbortController?.abort(YIELDED_TO_CHART)
            }
        },
        // A person refreshes the chart after a fix in the project's filter, which leaves the query as it was.
        loadDataSuccess: ({ payload }) => {
            actions.checkData(FORCED_REFRESHES.includes(payload?.refresh))
        },
        setFiltersTestAccounts: ({ filtersTestAccounts, check }) => {
            actions.updateQuerySource({ filterTestAccounts: filtersTestAccounts })
            if (filtersTestAccounts) {
                // pinned: analytics event name, renaming breaks dashboards
                posthog.capture('insight data check fix applied', { check })
            }
        },
        fixWithPostHogAI: ({ check }) => {
            // A second request while PostHog AI is open would start another run for the same finding.
            if (values.postHogAIOpen) {
                return
            }
            actions.openSidePanel(SidePanelTab.Max, autoRunMaxPrompt(postHogAIPromptOf(check)))
            posthog.capture('insight data check fix applied', { check: check.key, fix: 'posthog_ai' })
        },
        excludeFromInsight: ({ check }) => {
            // The checks still show the finding until they run again, so a second click would add the rule twice.
            if (values.status === 'checking') {
                return
            }
            const properties =
                check.filter_to_add &&
                withPropertyFilter(values.querySource?.properties, check.filter_to_add as AnyPropertyFilter)
            if (!properties) {
                return
            }
            actions.updateQuerySource({ properties })
            posthog.capture('insight data check fix applied', { check: check.key, fix: 'exclude_from_insight' })
        },
        addFilterRule: ({ check }) => {
            if (!check.filter_to_add) {
                return
            }
            actions.updateCurrentTeam({
                test_account_filters: [
                    ...(values.currentTeam?.test_account_filters ?? []),
                    check.filter_to_add as AnyPropertyFilter,
                ],
            })
            posthog.capture('insight data check fix applied', { check: check.key, fix: 'add_filter_rule' })
        },
        // The project's filter decides what the checks report, so they run again once it changes. A chart that applies
        // the filter loads again first, and its forced refresh runs the checks when it ends.
        updateCurrentTeamSuccess: ({ payload }) => {
            if (!payload || !('test_account_filters' in payload)) {
                return
            }
            const source = values.checkedQuery?.source
            if (source?.filterTestAccounts) {
                actions.loadData(shouldQueryBeAsync(source) ? 'force_async' : 'force_blocking')
            } else {
                actions.checkData(true)
            }
        },
        reportDataChecksViewed: () => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight data checks viewed', {
                status: values.status,
                findings: values.findings.map((check) => check.key),
            })
        },
        reportCheckExpanded: ({ check }) => {
            posthog.capture('insight data check expanded', {
                check: check.key,
                level: check.level,
                status: values.status,
            })
        },
        reportButtonClicked: ({ button, check }) => {
            posthog.capture('insight data check button clicked', { button, check, status: values.status })
        },
    })),
    // Also on mount, because the chart can finish loading before this logic mounts. A change such as the chart
    // type can reuse the chart's result, so no chart load follows it.
    subscriptions(({ actions, values }) => ({
        checkedQuery: () => {
            if (!values.insightDataLoading) {
                actions.checkData()
            }
        },
    })),
])
