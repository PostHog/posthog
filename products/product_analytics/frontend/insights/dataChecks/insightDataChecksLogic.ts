/** The insight query the server checks. The server reads the events from the query this chart runs. */
export interface DataChecksQuery {
    kind: NodeKind.InsightVizNode
    source: TrendsQuery | FunnelsQuery | StickinessQuery | LifecycleQuery
}

// A failed run is a value and not a loader error, so a check that fails in the background shows no error toast.
export type DataChecksRun = { ok: true; result: InsightDataChecksApi } | { ok: false; denied: boolean }

/** `unavailable`: the checks do not apply here. `checking`: the chart or the checks are still loading. */
export type InsightDataChecksStatus = 'unavailable' | 'checking' | 'failed' | InsightDataChecksStatusEnumApi

export type DataChecksButton =
    | 'filter_internal_users_on'
    | 'filter_internal_users_off'
    | 'add_filter_rule'
    | 'add_filter_rule_confirm'
    | 'edit_filter'
    | 'exclude_from_insight'
    | 'fix_with_posthog_ai'
    | 'see_repeated_events'
    | 'retry'

function statusOfRun(run: DataChecksRun): InsightDataChecksStatus {
    if (run.ok) {
        return run.result.status
    }
    return run.denied ? 'unavailable' : 'failed'
}

