export type insightDataChecksLogicType = MakeLogicType<
    insightDataChecksLogicValues,
    insightDataChecksLogicActions,
    InsightLogicProps,
    insightDataChecksLogicMeta
>

export const insightDataChecksLogic: LogicWrapper<insightDataChecksLogicType> = kea<insightDataChecksLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['products', 'product_analytics', 'insights', 'dataChecks', 'insightDataChecksLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            insightDataLogic(props),
            ['query'],
            insightVizDataLogic(props),
            ['insightDataLoading'],
            insightLogic(props),
            ['insight'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [insightVizDataLogic(props), ['loadDataFailure', 'loadDataSuccess', 'updateQuerySource']],
    })),
    actions({
        checkData: true,
        filterOutInternalUsers: true,
        reportDataChecksViewed: true,
        reportFixPromptSent: (check: InsightDataCheckApi, destination: string) => ({ check, destination }),
    }),
    loaders(({ values }) => ({
        dataChecksRun: [
            null as DataChecksRun | null,
            {
                loadDataChecks: async (query: DataChecksQuery): Promise<DataChecksRun | null> => {
                    let run: DataChecksRun
                    try {
                        const result = await insightsDataChecksCreate(String(getCurrentTeamId()), {
                            query,
                        } as unknown as InsightDataChecksRequestApi)
                        run = { ok: true, result }
                    } catch {
                        run = { ok: false }
                    }
                    // A newer run started while this one ran, so that run owns the result.
                    return values.requestedQuery === query ? run : values.dataChecksRun
                },
            },
        ],
    })),
    reducers({
        requestedQuery: [
            null as DataChecksQuery | null,
            {
                loadDataChecks: (_, query) => query,
            },
        ],
    }),
    selectors({
        // The server only checks insights whose series are all events, so no request goes out for the rest.
        // Trimmed and compared by value, so a change of chart type or breakdown is not a new query.
        checkedQuery: [
            (s) => [s.query, s.featureFlags],
            (query: Node | null, featureFlags: FeatureFlagsSet): DataChecksQuery | null => {
                if (!featureFlags[FEATURE_FLAGS.INSIGHT_DATA_CHECKS] || !isInsightVizNode(query)) {
                    return null
                }
                const source = query.source
                if (!isInsightQueryWithSeries(source) || !source.series.length || !source.series.every(isEventsNode)) {
                    return null
                }
                return {
                    kind: NodeKind.InsightVizNode,
                    source: {
                        kind: source.kind,
                        series: source.series.map((series) => ({ kind: NodeKind.EventsNode, event: series.event })),
                        dateRange: source.dateRange,
                        properties: source.properties,
                        filterTestAccounts: source.filterTestAccounts,
                    },
                }
            },
            { resultEqualityCheck: objectsEqual },
        ],
        result: [
            (s) => [s.dataChecksRun],
            (dataChecksRun: DataChecksRun | null): InsightDataChecksApi | null =>
                dataChecksRun?.ok ? dataChecksRun.result : null,
        ],
        status: [
            (s) => [s.checkedQuery, s.requestedQuery, s.dataChecksRunLoading, s.dataChecksRun],
            (
                checkedQuery: DataChecksQuery | null,
                requestedQuery: DataChecksQuery | null,
                dataChecksRunLoading: boolean,
                dataChecksRun: DataChecksRun | null
            ): InsightDataChecksStatus => {
                if (!checkedQuery) {
                    return 'unavailable'
                }
                // The checks run after the chart loads, so the last run is out of date from the moment the query changes.
                if (dataChecksRunLoading || !dataChecksRun || requestedQuery !== checkedQuery) {
                    return 'checking'
                }
                return dataChecksRun.ok ? dataChecksRun.result.status : 'failed'
            },
        ],
        checks: [
            (s) => [s.result],
            (result: InsightDataChecksApi | null): InsightDataCheckApi[] => result?.checks ?? [],
        ],
        findings: [
            (s) => [s.checks],
            (checks: InsightDataCheckApi[]): InsightDataCheckApi[] =>
                checks.filter((check) => check.level === 'warning' || check.level === 'problem'),
        ],
        promptContext: [
            (s) => [s.checkedQuery, s.insight, s.result],
            (
                checkedQuery: DataChecksQuery | null,
                insight: Partial<InsightModel>,
                result: InsightDataChecksApi | null
            ): DataCheckPromptContext | null => {
                if (!result || !checkedQuery) {
                    return null
                }
                const names = checkedQuery.source.series.map((series) => series.event)
                return {
                    insightUrl: insight.short_id
                        ? urls.absolute(urls.currentProject(urls.insightView(insight.short_id)))
                        : null,
                    events: names.every((name): name is string => !!name) ? [...new Set(names)] : 'all',
                    eventsChecked: result.events_checked,
                    sampled: result.sample_rate < 1,
                }
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        // The chart can load more than once for one query, and the answer for that query is already on its way.
        checkData: () => {
            const query = values.checkedQuery
            if (query && query !== values.requestedQuery) {
                actions.loadDataChecks(query)
            }
        },
        loadDataSuccess: () => {
            actions.checkData()
        },
        // The checks read the events directly, so they can run when the chart itself fails.
        loadDataFailure: () => {
            actions.checkData()
        },
        filterOutInternalUsers: () => {
            actions.updateQuerySource({ filterTestAccounts: true })
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight data check fix applied', { check: 'internal_users' })
        },
        reportFixPromptSent: ({ check, destination }) => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight data check fix prompt sent', { check: check.key, level: check.level, destination })
        },
        reportDataChecksViewed: () => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('insight data checks viewed', {
                status: values.status,
                findings: values.findings.map((check) => check.key),
            })
        },
    })),
    // The chart can finish loading before this logic mounts.
    afterMount(({ actions, values }) => {
        if (!values.insightDataLoading) {
            actions.checkData()
        }
    }),
])
