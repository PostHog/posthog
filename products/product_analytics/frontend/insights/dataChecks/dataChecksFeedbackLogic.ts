import {
    MakeLogicType,
    LogicWrapper,
    actions,
    afterMount,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
    selectors,
} from 'kea'
import posthog, { Survey } from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { uuid } from 'lib/utils/dom'
import { getSurveyIdBasedResponseKey } from 'scenes/surveys/utils'

import { SurveyEventName, SurveyEventProperties } from '~/types'

export const DATA_CHECKS_FEEDBACK_SURVEY_ID = '01a15d5f-3117-0000-9b74-1712010c28ca'

// A two-point thumbs rating stores 1 for thumbs up and 2 for thumbs down.
export const DATA_CHECKS_FEEDBACK_RATINGS = { USEFUL: '1', NOT_USEFUL: '2' } as const
export type DataChecksFeedbackRating = (typeof DATA_CHECKS_FEEDBACK_RATINGS)[keyof typeof DATA_CHECKS_FEEDBACK_RATINGS]

export interface DataChecksFeedbackLogicProps {
    userId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataChecksFeedbackLogicValues {
    finished: boolean
    note: string
    noteSent: boolean
    rating: DataChecksFeedbackRating | null
    shownReported: boolean
    submissionId: string
    survey: Survey | null
    surveyProperties: Record<string, unknown>
    visible: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataChecksFeedbackLogicActions {
    dismiss: () => {
        value: true
    }
    rate: (rating: DataChecksFeedbackRating) => {
        rating: DataChecksFeedbackRating
        submissionId: string
    }
    rateFailure: () => {
        value: true
    }
    rateSuccess: () => {
        value: true
    }
    reportShown: () => {
        value: true
    }
    setNote: (note: string) => {
        note: string
    }
    setSurvey: (survey: Survey | null) => {
        survey: Survey | null
    }
    submitNote: () => {
        value: true
    }
    submitNoteSuccess: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataChecksFeedbackLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        visible: (survey: Survey | null, finished: boolean, rating: DataChecksFeedbackRating | null) => boolean
        surveyProperties: (survey: Survey | null) => Record<string, unknown>
    }
}

export type dataChecksFeedbackLogicType = MakeLogicType<
    dataChecksFeedbackLogicValues,
    dataChecksFeedbackLogicActions,
    DataChecksFeedbackLogicProps,
    dataChecksFeedbackLogicMeta
>

export const dataChecksFeedbackLogic: LogicWrapper<dataChecksFeedbackLogicType> = kea<dataChecksFeedbackLogicType>([
    props({} as DataChecksFeedbackLogicProps),
    key(({ userId }) => userId),
    path((key) => ['products', 'product_analytics', 'insights', 'dataChecks', 'dataChecksFeedbackLogic', key]),
    actions({
        setSurvey: (survey: Survey | null) => ({ survey }),
        reportShown: true,
        rate: (rating: DataChecksFeedbackRating) => ({ rating, submissionId: uuid() }),
        rateSuccess: true,
        rateFailure: true,
        setNote: (note: string) => ({ note }),
        submitNote: true,
        submitNoteSuccess: true,
        dismiss: true,
    }),
    reducers(({ props }) => ({
        survey: [null as Survey | null, { setSurvey: (_, { survey }) => survey }],
        shownReported: [false, { reportShown: () => true }],
        rating: [null as DataChecksFeedbackRating | null, { rate: (_, { rating }) => rating, rateFailure: () => null }],
        submissionId: ['', { rate: (_, { submissionId }) => submissionId }],
        note: ['', { setNote: (_, { note }) => note }],
        noteSent: [false, { submitNoteSuccess: () => true }],
        // pinned: localStorage key, renaming it asks everyone again
        finished: [
            false,
            { persist: true, storageKey: `insight-data-checks-feedback-finished:${props.userId}` },
            { rateSuccess: () => true, dismiss: () => true },
        ],
    })),
    selectors({
        visible: [
            (s) => [s.survey, s.finished, s.rating],
            (survey: Survey | null, finished: boolean, rating: DataChecksFeedbackRating | null): boolean =>
                !!survey && (!finished || rating !== null),
        ],
        surveyProperties: [
            (s) => [s.survey],
            (survey: Survey | null): Record<string, unknown> => ({
                [SurveyEventProperties.SURVEY_ID]: survey?.id,
                $survey_name: survey?.name,
            }),
        ],
    }),
    listeners(({ actions, values }) => ({
        reportShown: () => {
            posthog.capture(SurveyEventName.SHOWN, values.surveyProperties)
        },
        rate: ({ rating, submissionId }) => {
            const [ratingQuestion] = values.survey?.questions ?? []
            const sent = posthog.capture(SurveyEventName.SENT, {
                ...values.surveyProperties,
                [SurveyEventProperties.SURVEY_SUBMISSION_ID]: submissionId,
                [SurveyEventProperties.SURVEY_COMPLETED]: false,
                ...(ratingQuestion?.id ? { [getSurveyIdBasedResponseKey(ratingQuestion.id)]: rating } : {}),
            })
            if (sent) {
                actions.rateSuccess()
            } else {
                actions.rateFailure()
                lemonToast.error('Could not send your feedback. Try again.')
            }
        },
        submitNote: () => {
            const [ratingQuestion, noteQuestion] = values.survey?.questions ?? []
            const note = values.note.trim()
            const sent = posthog.capture(SurveyEventName.SENT, {
                ...values.surveyProperties,
                [SurveyEventProperties.SURVEY_SUBMISSION_ID]: values.submissionId,
                [SurveyEventProperties.SURVEY_COMPLETED]: true,
                ...(ratingQuestion?.id ? { [getSurveyIdBasedResponseKey(ratingQuestion.id)]: values.rating } : {}),
                ...(noteQuestion?.id && note ? { [getSurveyIdBasedResponseKey(noteQuestion.id)]: note } : {}),
            })
            if (sent) {
                actions.submitNoteSuccess()
            } else {
                lemonToast.error('Could not send your feedback. Try again.')
            }
        },
        dismiss: () => {
            posthog.capture(SurveyEventName.DISMISSED, values.surveyProperties)
        },
    })),
    afterMount(({ actions, values, cache }) => {
        // The survey links to a feature flag, so it can only match once both surveys and flags have loaded.
        // A sent rating marks the survey as answered, so keep it after the rating while the person writes a note.
        const findSurvey = (): void => {
            posthog.getActiveMatchingSurveys((surveys) => {
                if (values.rating === null) {
                    actions.setSurvey(surveys.find(({ id }) => id === DATA_CHECKS_FEEDBACK_SURVEY_ID) ?? null)
                }
            })
        }
        cache.disposables.add(() => posthog.onSurveysLoaded(findSurvey), 'surveysLoaded')
        cache.disposables.add(() => posthog.onFeatureFlags(findSurvey), 'flagsLoaded')
    }),
])
