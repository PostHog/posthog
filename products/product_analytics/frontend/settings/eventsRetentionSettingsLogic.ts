export interface eventsRetentionSettingsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        retentionOptions: (eventsRetention: EventsRetentionApi | null) => EventsRetentionOption[]
    }
}

export type eventsRetentionSettingsLogicType = MakeLogicType<
    eventsRetentionSettingsLogicValues,
    eventsRetentionSettingsLogicActions,
    Record<string, any>,
    eventsRetentionSettingsLogicMeta
>

export const eventsRetentionSettingsLogic = kea<eventsRetentionSettingsLogicType>([
    path(['products', 'product_analytics', 'frontend', 'settings', 'eventsRetentionSettingsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    loaders(({ values }) => ({
        eventsRetention: [
            null as EventsRetentionApi | null,
            {
                loadEventsRetention: async () => {
                    if (values.currentTeamId === null) {
                        return null
                    }
                    return await api.eventsRetentionRetrieve(String(values.currentTeamId))
                },
                updateEventsRetention: async (retentionMonths: EventsRetentionWindowEnumApi) => {
                    if (values.currentTeamId === null) {
                        return values.eventsRetention
                    }
                    return await api.eventsRetentionUpdate(String(values.currentTeamId), {
                        retention_months: retentionMonths,
                    })
                },
            },
        ],
    })),
    selectors({
        retentionOptions: [
            (s) => [s.eventsRetention],
            (eventsRetention: EventsRetentionApi | null): EventsRetentionOption[] => {
                const maxRetentionMonths = eventsRetention?.max_retention_months ?? 0
                return EVENTS_RETENTION_OPTIONS.map(({ value, label, upgradeReason }) => ({
                    value,
                    label,
                    disabledReason: value > maxRetentionMonths ? upgradeReason : undefined,
                }))
            },
        ],
    }),
    listeners(() => ({
        updateEventsRetentionSuccess: () => {
            lemonToast.success('Events retention updated')
            dataRetentionBannerLogic.findMounted()?.actions.loadRetentionMonths()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadEventsRetention()
    }),
])
