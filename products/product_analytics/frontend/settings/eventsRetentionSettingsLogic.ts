export interface eventsRetentionSettingsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        retentionOptions: (organizationRetention: OrganizationEventsRetentionApi | null) => EventsRetentionOption[]
        selectedRetentionMonths: (organizationRetention: OrganizationEventsRetentionApi | null) => number | null
    }
}

export type eventsRetentionSettingsLogicType = MakeLogicType<
    eventsRetentionSettingsLogicValues,
    eventsRetentionSettingsLogicActions,
    Record<string, any>,
    eventsRetentionSettingsLogicMeta
>

export const eventsRetentionSettingsLogic = kea<eventsRetentionSettingsLogicType>([
    path(['products', 'product_analytics', 'frontend', 'settings', 'eventsRetentionSettingsLogic']),
    connect(() => ({
        values: [organizationLogic, ['currentOrganizationId'], dataRetentionBannerLogic, ['retentionEnforced']],
    })),
    loaders(({ values }) => ({
        organizationRetention: [
            null as OrganizationEventsRetentionApi | null,
            {
                loadOrganizationRetention: async () => {
                    if (!values.currentOrganizationId) {
                        return null
                    }
                    return await api.organizationEventsRetentionRetrieve(values.currentOrganizationId)
                },
                updateOrganizationRetention: async (retentionMonths: EventsRetentionWindowEnumApi) => {
                    if (!values.currentOrganizationId) {
                        return values.organizationRetention
                    }
                    return await api.organizationEventsRetentionUpdate(values.currentOrganizationId, {
                        retention_months: retentionMonths,
                    })
                },
            },
        ],
    })),
    selectors({
        retentionOptions: [
            (s) => [s.organizationRetention],
            (organizationRetention: OrganizationEventsRetentionApi | null): EventsRetentionOption[] => {
                const maxRetentionMonths = organizationRetention?.max_retention_months ?? 0
                return EVENTS_RETENTION_OPTIONS.map(({ value, label, upgradeReason }) => ({
                    value,
                    label,
                    disabledReason: value > maxRetentionMonths ? upgradeReason : undefined,
                }))
            },
        ],
        selectedRetentionMonths: [
            (s) => [s.organizationRetention],
            (organizationRetention: OrganizationEventsRetentionApi | null): number | null =>
                organizationRetention
                    ? Math.min(
                          organizationRetention.retention_months ?? organizationRetention.max_retention_months,
                          organizationRetention.max_retention_months
                      )
                    : null,
        ],
    }),
    listeners(() => ({
        updateOrganizationRetentionSuccess: () => {
            lemonToast.success('Events retention updated')
            dataRetentionBannerLogic.findMounted()?.actions.loadRetentionMonths()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadOrganizationRetention()
    }),
])
