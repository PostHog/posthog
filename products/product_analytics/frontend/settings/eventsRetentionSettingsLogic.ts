export type eventsRetentionSettingsLogicType = MakeLogicType<
    eventsRetentionSettingsLogicValues,
    eventsRetentionSettingsLogicActions
>

export const eventsRetentionSettingsLogic = kea<eventsRetentionSettingsLogicType>([
    path(['products', 'product_analytics', 'frontend', 'settings', 'eventsRetentionSettingsLogic']),
    connect(() => ({
        values: [organizationLogic, ['currentOrganizationId'], teamLogic, ['currentTeamId']],
    })),
    loaders(({ values }) => ({
        projectRetention: [
            null as EventsRetentionApi | null,
            {
                loadProjectRetention: async () => {
                    if (values.currentTeamId === null) {
                        return null
                    }
                    return await api.eventsRetentionRetrieve(String(values.currentTeamId))
                },
                updateProjectRetention: async (retentionMonths: number | null) => {
                    if (values.currentTeamId === null) {
                        return values.projectRetention
                    }
                    return await api.eventsRetentionUpdate(String(values.currentTeamId), {
                        retention_months: retentionMonths,
                    })
                },
            },
        ],
        projectImpact: [
            null as EventsRetentionImpactApi | null,
            {
                loadProjectImpact: async (retentionMonths: number, breakpoint) => {
                    await breakpoint(300)
                    if (values.currentTeamId === null) {
                        return null
                    }
                    return await api.eventsRetentionImpact(String(values.currentTeamId), {
                        retention_months: retentionMonths,
                    })
                },
            },
        ],
        organizationImpact: [
            null as EventsRetentionImpactApi | null,
            {
                loadOrganizationImpact: async (retentionMonths: number, breakpoint) => {
                    await breakpoint(300)
                    if (!values.currentOrganizationId) {
                        return null
                    }
                    return await api.organizationEventsRetentionImpact(values.currentOrganizationId, {
                        retention_months: retentionMonths,
                    })
                },
            },
        ],
        organizationRetention: [
            null as OrganizationEventsRetentionApi | null,
            {
                loadOrganizationRetention: async () => {
                    if (!values.currentOrganizationId) {
                        return null
                    }
                    return await api.organizationEventsRetentionRetrieve(values.currentOrganizationId)
                },
                updateOrganizationRetention: async (retentionMonths: number | null) => {
                    if (!values.currentOrganizationId) {
                        return values.organizationRetention
                    }
                    return await api.organizationEventsRetentionUpdate(values.currentOrganizationId, {
                        retention_months: retentionMonths,
                    })
                },
            },
        ],
    })),
    listeners(({ actions }) => ({
        updateProjectRetentionSuccess: () => {
            lemonToast.success('Events retention updated')
            dataRetentionBannerLogic.findMounted()?.actions.loadRetentionMonths()
        },
        updateOrganizationRetentionSuccess: () => {
            lemonToast.success('Events retention updated')
            actions.loadProjectRetention()
            dataRetentionBannerLogic.findMounted()?.actions.loadRetentionMonths()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadProjectRetention()
        actions.loadOrganizationRetention()
    }),
])
