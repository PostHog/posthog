import { MakeLogicType, afterMount, connect, kea, listeners, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { dataRetentionBannerLogic } from 'scenes/insights/dataRetention/dataRetentionBannerLogic'
import { organizationLogic } from 'scenes/organizationLogic'

import * as api from 'products/product_analytics/frontend/generated/api'
import type {
    EventsRetentionWindowEnumApi,
    OrganizationEventsRetentionApi,
} from 'products/product_analytics/frontend/generated/api.schemas'

export interface EventsRetentionOption {
    value: EventsRetentionWindowEnumApi
    label: string
    disabledReason?: string
}

const EVENTS_RETENTION_OPTIONS: { value: EventsRetentionWindowEnumApi; label: string; upgradeReason: string }[] = [
    { value: 12, label: '1 year', upgradeReason: '' },
    { value: 24, label: '2 years', upgradeReason: 'Available on the pay-as-you-go plan' },
    { value: 36, label: '3 years', upgradeReason: 'Available with the Boost, Scale, or Enterprise package' },
    { value: 60, label: '5 years', upgradeReason: 'Available with the Scale or Enterprise package' },
    { value: 84, label: '7 years', upgradeReason: 'Available with the Enterprise package' },
]

