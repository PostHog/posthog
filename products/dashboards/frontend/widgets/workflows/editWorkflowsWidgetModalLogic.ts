export const editWorkflowsWidgetModalLogic = kea<editWorkflowsWidgetModalLogicType>([
    path(['products', 'dashboards', 'widgets', 'workflows', 'editWorkflowsWidgetModalLogic']),
    props({} as EditWorkflowsWidgetModalLogicProps),
    actions({
        ...widgetEditModalTileActions,
        setLimit: (limit: number) => ({ limit }),
        submit: true,
        submitSuccess: true,
        submitFailure: true,
    }),
    reducers({
        limit: [10, { setLimit: (_state: number, { limit }: { limit: number }) => limit }],
        tileName: ['', { setTileName: (_state: string, { tileName }: { tileName: string }) => tileName }],
        tileDescription: [
            '',
            {
                setTileDescription: (_state: string, { tileDescription }: { tileDescription: string }) =>
                    tileDescription,
            },
        ],
        saving: [false, { submit: () => true, submitSuccess: () => false, submitFailure: () => false }],
        defaultTitle: ['Workflow activity'],
    }),
    selectors({
        config: [
            (_state, props) => [props.config],
            (config: Record<string, unknown>): WorkflowsWidgetConfig => workflowsWidgetConfigSchema.parse(config),
        ],
        onClose: [(_state, props) => [props.onClose], (onClose: () => void): (() => void) => onClose],
    }),
    listeners(({ actions, values, props }) => ({
        submit: async () => {
            try {
                // Status, type and date range live on the tile bar; spreading the persisted config keeps them.
                const config = workflowsWidgetConfigSchema.parse({ ...values.config, limit: values.limit })
                await props.onSave(config, buildWidgetTileMetadataPatch(props, values.tileName, values.tileDescription))
                actions.submitSuccess()
                props.onClose()
            } catch {
                actions.submitFailure()
                lemonToast.error('Could not save widget settings. Check your connection and try again.')
            }
        },
    })),
    afterMount(({ actions, props }) => {
        const config = workflowsWidgetConfigSchema.parse(props.config)
        const metadata = getWidgetEditModalTileDefaults(props)
        actions.setLimit(config.limit ?? 10)
        actions.setTileName(metadata.tileName)
        actions.setTileDescription(metadata.tileDescription)
    }),
])
