import { MakeLogicType, actions, defaults, kea, listeners, path, props, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { LemonDialog } from 'lib/lemon-ui/LemonDialog'
import { objectsEqual } from 'lib/utils/objects'

import { MetricsQuery, NodeKind } from '~/queries/schema/schema-general'

import {
    isMetricsHeatmapQuery,
    metricsHeatmapIneligibleReason,
} from 'products/metrics/frontend/widgets/metricsHeatmapQuery'

import { isWidgetConfigValidationError } from '../../utils'
import {
    buildWidgetTileMetadataPatch,
    getWidgetEditModalTileDefaults,
    widgetEditModalPropSelectors,
    widgetEditModalTileActions,
} from '../editWidgetModalBuilders'
import type { DashboardWidgetEditModalProps } from '../registry'
import { metricsWidgetNeedsConfiguration, metricsWidgetQuery } from './metricsWidgetConfig'
import type { MetricsWidgetFieldErrors } from './metricsWidgetConfigValidation'

export type EditMetricsWidgetModalLogicProps = Omit<DashboardWidgetEditModalProps, 'isOpen'>

