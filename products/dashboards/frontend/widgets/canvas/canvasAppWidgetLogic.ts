/**
 * Loads the live build of the canvas a tile points at, with the viewer's own session, so the
 * tile renders exactly what the canvas scene would show this viewer.
 */
export const canvasAppWidgetLogic = kea<canvasAppWidgetLogicType>([
    path((key) => ['products', 'dashboards', 'widgets', 'canvas', 'canvasAppWidgetLogic', key]),
    props({} as CanvasAppWidgetLogicProps),
    key((props) => `${props.tileId}:${props.canvasId}`),

    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),

    loaders(({ props, values }) => ({
        view: [
            null as CanvasViewResponseApi | null,
            {
                loadView: async (): Promise<CanvasViewResponseApi> =>
                    canvasesViewRetrieve(String(values.currentProjectId), props.canvasId),
            },
        ],
    })),

    reducers({
        viewFailed: [
            false,
            {
                loadView: () => false,
                loadViewFailure: () => true,
            },
        ],
    }),

    selectors(({ props }) => ({
        renderState: [
            (s) => [s.view, s.viewLoading, s.viewFailed],
            (view: CanvasViewResponseApi | null, viewLoading: boolean, viewFailed: boolean): CanvasAppRenderState => {
                if (viewFailed) {
                    return 'error'
                }
                if (!view || viewLoading) {
                    return view?.published_build?.artifact_url ? 'built' : 'loading'
                }
                return view.published_build?.artifact_url ? 'built' : 'not-published'
            },
        ],
        artifactUrl: [
            (s) => [s.view],
            (view: CanvasViewResponseApi | null): string | null => view?.published_build?.artifact_url ?? null,
        ],
        capabilities: [
            (s) => [s.view],
            (view: CanvasViewResponseApi | null): CanvasCapabilitiesApi | null =>
                (view?.published_build?.manifest?.capabilities as CanvasCapabilitiesApi | undefined) ?? null,
        ],
        buildId: [
            (s) => [s.view],
            (view: CanvasViewResponseApi | null): string | null => view?.published_build?.id ?? null,
        ],
        hostProps: [
            (s) => [s.view],
            (view: CanvasViewResponseApi | null): CanvasHostLogicProps => ({
                canvasId: props.canvasId,
                spaceId: view?.canvas.channel ?? null,
                sourceVersionId: view?.published_build?.source_version_id ?? view?.current_version_id ?? null,
            }),
        ],
    })),

    afterMount(({ actions }) => {
        actions.loadView()
    }),
])
