import { MakeLogicType, afterMount, connect, kea, key, path, props, propsChanged, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { canvasesViewRetrieve } from 'products/canvas/frontend/generated/api'
import type { CanvasCapabilitiesApi, CanvasViewResponseApi } from 'products/canvas/frontend/generated/api.schemas'
import type { CanvasHostLogicProps } from 'products/canvas/frontend/host/canvasHostLogic'

export type CanvasAppWidgetLogicProps = {
    tileId: number
    canvasId: string
    /** The live build the dashboard result reports. When it changes, the tile loads the view again. */
    publishedBuildId?: string | null
}

export type CanvasAppRenderState = 'loading' | 'built' | 'not-published' | 'unavailable' | 'error'

// The viewer lost access to the canvas, or someone deleted it, after the dashboard result loaded.
const UNAVAILABLE_STATUSES = new Set([403, 404])

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface canvasAppWidgetLogicValues {
    currentProjectId: number | string // teamLogic
    artifactUrl: string | null
    buildId: string | null
    capabilities: CanvasCapabilitiesApi | null
    hostProps: CanvasHostLogicProps
    renderState: CanvasAppRenderState
    view: CanvasViewResponseApi | null
    viewFailed: boolean
    viewFailureStatus: number | null
    viewLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface canvasAppWidgetLogicActions {
    loadView: () => any
    loadViewFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadViewSuccess: (
        view: CanvasViewResponseApi,
        payload?: any
    ) => {
        view: CanvasViewResponseApi
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface canvasAppWidgetLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        renderState: (
            view: CanvasViewResponseApi | null,
            viewLoading: boolean,
            viewFailed: boolean,
            viewFailureStatus: number | null
        ) => CanvasAppRenderState
        artifactUrl: (view: CanvasViewResponseApi | null) => string | null
        capabilities: (view: CanvasViewResponseApi | null) => CanvasCapabilitiesApi | null
        buildId: (view: CanvasViewResponseApi | null) => string | null
        hostProps: (view: CanvasViewResponseApi | null) => CanvasHostLogicProps
    }
}

export type canvasAppWidgetLogicType = MakeLogicType<
    canvasAppWidgetLogicValues,
    canvasAppWidgetLogicActions,
    CanvasAppWidgetLogicProps,
    canvasAppWidgetLogicMeta
>

/**
 * Loads the live build of the canvas a tile points at, with the viewer's own session, so the
 * tile renders exactly what the canvas scene would show this viewer.
 */
export const canvasAppWidgetLogic = kea<canvasAppWidgetLogicType>([
    path((key) => ['products', 'dashboards', 'widgets', 'canvas', 'canvasAppWidgetLogic', key]),
    props({} as CanvasAppWidgetLogicProps),
    key((props) => `${props.tileId}:${props.canvasId}`),

    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),

    loaders(({ props, values }) => ({
        view: [
            null as CanvasViewResponseApi | null,
            {
                loadView: async (): Promise<CanvasViewResponseApi> =>
                    canvasesViewRetrieve(String(values.currentProjectId), props.canvasId),
            },
        ],
    })),

    reducers({
        viewFailed: [
            false,
            {
                loadView: () => false,
                loadViewFailure: () => true,
            },
        ],
        viewFailureStatus: [
            null as number | null,
            {
                loadView: () => null,
                loadViewFailure: (_, { errorObject }) =>
                    typeof errorObject?.status === 'number' ? errorObject.status : null,
            },
        ],
    }),

    selectors(({ props }) => ({
        renderState: [
            (s) => [s.view, s.viewLoading, s.viewFailed, s.viewFailureStatus],
            (
                view: CanvasViewResponseApi | null,
                viewLoading: boolean,
                viewFailed: boolean,
                viewFailureStatus: number | null
            ): CanvasAppRenderState => {
                if (viewFailed) {
                    return viewFailureStatus !== null && UNAVAILABLE_STATUSES.has(viewFailureStatus)
                        ? 'unavailable'
                        : 'error'
                }
                if (!view || viewLoading) {
                    return view?.published_build?.artifact_url ? 'built' : 'loading'
                }
                return view.published_build?.artifact_url ? 'built' : 'not-published'
            },
        ],
        artifactUrl: [
            (s) => [s.view],
            (view: CanvasViewResponseApi | null): string | null => view?.published_build?.artifact_url ?? null,
        ],
        capabilities: [
            (s) => [s.view],
            (view: CanvasViewResponseApi | null): CanvasCapabilitiesApi | null =>
                (view?.published_build?.manifest?.capabilities as CanvasCapabilitiesApi | undefined) ?? null,
        ],
        buildId: [
            (s) => [s.view],
            (view: CanvasViewResponseApi | null): string | null => view?.published_build?.id ?? null,
        ],
        hostProps: [
            (s) => [s.view],
            (view: CanvasViewResponseApi | null): CanvasHostLogicProps => ({
                canvasId: props.canvasId,
                spaceId: view?.canvas.channel ?? null,
                sourceVersionId: view?.published_build?.source_version_id ?? view?.current_version_id ?? null,
                // Two tiles can show the same canvas. Each tile gets its own prompts and bridge state.
                instanceKey: `dashboard-tile-${props.tileId}`,
            }),
        ],
    })),

    afterMount(({ actions }) => {
        actions.loadView()
    }),

    propsChanged(({ actions, props }, oldProps) => {
        // A dashboard refresh can report a new live build. The view loads only on mount, so load it again.
        if (props.publishedBuildId !== oldProps.publishedBuildId) {
            actions.loadView()
        }
    }),
])
