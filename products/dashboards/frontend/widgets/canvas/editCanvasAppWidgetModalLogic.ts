export const editCanvasAppWidgetModalLogic = kea<editCanvasAppWidgetModalLogicType>([
    path(['products', 'dashboards', 'widgets', 'canvas', 'editCanvasAppWidgetModalLogic']),

    props({
        config: {},
        onSave: async () => {},
        onClose: () => {},
        name: '',
        defaultTitle: 'Untitled',
        description: '',
    } as EditCanvasAppWidgetModalLogicProps),

    actions({
        ...widgetEditModalTileActions,
        setCanvasId: (canvasId: string | null) => ({ canvasId }),
        setFieldErrors: (fieldErrors: CanvasAppWidgetFieldErrors) => ({ fieldErrors }),
        clearFieldError: (field: keyof CanvasAppWidgetFieldErrors) => ({ field }),
        submit: true,
        submitSuccess: true,
        submitFailure: true,
    }),

    reducers({
        canvasId: [
            null as string | null,
            {
                setCanvasId: (_: string | null, { canvasId }: { canvasId: string | null }) => canvasId,
            },
        ],
        tileName: [
            '',
            {
                setTileName: (_: string, { tileName }: { tileName: string }) => tileName,
            },
        ],
        tileDescription: [
            '',
            {
                setTileDescription: (_: string, { tileDescription }: { tileDescription: string }) => tileDescription,
            },
        ],
        fieldErrors: [
            {} as CanvasAppWidgetFieldErrors,
            {
                setFieldErrors: (
                    _: CanvasAppWidgetFieldErrors,
                    { fieldErrors }: { fieldErrors: CanvasAppWidgetFieldErrors }
                ) => fieldErrors,
                clearFieldError: (
                    state: CanvasAppWidgetFieldErrors,
                    { field }: { field: keyof CanvasAppWidgetFieldErrors }
                ) => {
                    if (!state[field]) {
                        return state
                    }
                    const next = { ...state }
                    delete next[field]
                    return next
                },
            },
        ],
        saving: [
            false,
            {
                submit: (_state: boolean, _payload: { value: true }) => true,
                submitSuccess: (_state: boolean, _payload: { value: true }) => false,
                submitFailure: (_state: boolean, _payload: { value: true }) => false,
            },
        ],
    }),

    selectors({
        ...widgetEditModalPropSelectors,
        validation: [
            (s) => [s.canvasId],
            (canvasId: string | null): CanvasAppValidation => validateCanvasAppWidgetConfigInput({ canvasId }),
        ],
        activeFieldErrors: [
            (s) => [s.validation, s.fieldErrors],
            (validation: CanvasAppValidation, fieldErrors: CanvasAppWidgetFieldErrors): CanvasAppWidgetFieldErrors => {
                if (!validation.success) {
                    return { ...validation.fieldErrors, ...fieldErrors }
                }
                return fieldErrors
            },
        ],
        saveDisabledReason: [
            (s) => [s.saving, s.validation],
            (saving: boolean, validation: CanvasAppValidation): string | undefined => {
                if (saving) {
                    return 'Saving…'
                }
                if (!validation.success) {
                    return 'Fix validation errors to save'
                }
                return undefined
            },
        ],
    }),

    defaults(({ props }) => ({
        canvasId: parseCanvasAppWidgetConfig(props.config).canvasId ?? null,
        ...getWidgetEditModalTileDefaults(props),
        fieldErrors: {},
        saving: false,
    })),

    listeners(({ actions, props, values }) => ({
        submit: async () => {
            const result = values.validation

            if (!result.success) {
                actions.setFieldErrors(result.fieldErrors)
                return
            }

            try {
                await props.onSave(
                    result.config,
                    buildWidgetTileMetadataPatch(props, values.tileName, values.tileDescription)
                )
                actions.setFieldErrors({})
                props.onClose()
                actions.submitSuccess()
            } catch (error) {
                actions.submitFailure()
                if (isWidgetConfigValidationError(error)) {
                    actions.setFieldErrors(error.fieldErrors as CanvasAppWidgetFieldErrors)
                    return
                }
                throw error
            }
        },
    })),
])
