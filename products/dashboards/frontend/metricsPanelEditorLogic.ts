import { LemonDialog } from 'lib/lemon-ui/LemonDialog'
import { accessLevelSatisfied } from 'lib/utils/accessControlUtils'
import { objectsEqual } from 'lib/utils/objects'

import { isMetricsQuery } from '~/queries/schema/node-guards'
import { DashboardFilter, MetricsQuery } from '~/queries/schema/schema-general'
import { AccessControlLevel, AccessControlResourceType } from '~/types'

import { insightsPartialUpdate, insightsRetrieve } from 'products/product_analytics/frontend/generated/api'
import type { InsightApi } from 'products/product_analytics/frontend/generated/api.schemas'

