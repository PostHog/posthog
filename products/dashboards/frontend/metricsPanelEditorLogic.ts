export const metricsPanelEditorLogic: LogicWrapper<metricsPanelEditorLogicType> = kea<metricsPanelEditorLogicType>([
    props({} as MetricsPanelEditorProps),
    key(({ projectId, insightId }) => `${projectId}.${insightId}`),
    path((key) => ['products', 'dashboards', 'metricsPanelEditorLogic', key]),
    actions({
        setQuery: (query: MetricsQuery) => ({ query }),
        setName: (name: string) => ({ name }),
        save: true,
        saveSuccess: true,
        saveFailure: (error: string) => ({ error }),
        requestClose: true,
    }),
    loaders(({ props }) => ({
        original: [
            null as InsightApi | null,
            {
                loadInsight: async () => {
                    const insight = await insightsRetrieve(String(props.projectId), props.insightId)
                    if (!isMetricsQuery(insight.query)) {
                        throw new Error('This panel needs the full insight editor.')
                    }
                    return insight
                },
            },
        ],
    })),
    reducers({
        query: [null as MetricsQuery | null, { setQuery: (_, { query }) => query }],
        name: ['', { setName: (_, { name }) => name }],
        saving: [false, { save: () => true, saveSuccess: () => false, saveFailure: () => false }],
        error: [
            null as string | null,
            {
                loadInsight: () => null,
                loadInsightFailure: (_, { error }) => error,
                save: () => null,
                saveFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        dirty: [
            (s) => [s.original, s.query, s.name],
            (original: InsightApi | null, query: MetricsQuery | null, name: string): boolean =>
                !!original && (!objectsEqual(original.query, query) || (original.name ?? '') !== name),
        ],
        dashboardCount: [
            (s) => [s.original],
            (original: InsightApi | null): number =>
                new Set(original?.dashboard_tiles.filter((tile) => !tile.deleted).map((tile) => tile.dashboard_id))
                    .size,
        ],
        saveDisabledReason: [
            (s) => [s.original, s.query, s.dirty, s.originalLoading],
            (
                original: InsightApi | null,
                query: MetricsQuery | null,
                dirty: boolean,
                loading: boolean
            ): string | undefined => {
                if (loading || !original || !query) {
                    return 'Loading the saved insight'
                }
                if (
                    !accessLevelSatisfied(
                        AccessControlResourceType.Insight,
                        original.user_access_level as AccessControlLevel,
                        AccessControlLevel.Editor
                    )
                ) {
                    return 'You need edit access to this insight'
                }
                if (
                    query.language === 'promql'
                        ? !query.promql?.trim()
                        : query.language === 'sql'
                          ? !query.sql?.trim()
                          : !query.clauses.length
                ) {
                    return 'Choose a metric or write a query'
                }
                return dirty ? undefined : 'Make a change to save'
            },
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        loadInsightSuccess: ({ original }) => {
            if (isMetricsQuery(original.query)) {
                actions.setQuery(original.query)
                actions.setName(original.name ?? '')
            }
        },
        save: async () => {
            if (cache.saving) {
                return
            }
            if (values.saveDisabledReason || !values.query) {
                actions.saveFailure(values.saveDisabledReason ?? 'Load the insight before saving')
                return
            }
            cache.saving = true
            const { name, query } = values
            try {
                await insightsPartialUpdate(String(props.projectId), props.insightId, { name, query })
                actions.saveSuccess()
                props.onSaved()
                props.onClose()
            } catch (error: any) {
                actions.saveFailure(error.detail ?? error.message ?? 'Could not save the panel. Try again.')
            } finally {
                cache.saving = false
            }
        },
        requestClose: () => {
            if (values.saving) {
                return
            }
            if (!values.dirty) {
                props.onClose()
                return
            }
            LemonDialog.open({
                title: 'Discard panel changes?',
                description: 'Your saved insight will keep its current settings.',
                primaryButton: { children: 'Discard changes', onClick: props.onClose },
                secondaryButton: { children: 'Keep editing' },
            })
        },
    })),
    afterMount(({ actions }) => actions.loadInsight()),
])
