const emptySavedViewCursors: DashboardSavedViewCursors = { private: null, team: null }

function isSavedViewsUnavailableError(error: unknown): boolean {
    return error instanceof ApiError && (error.status === 403 || error.status === 404)
}

export function dashboardListSavedView(view: DashboardSavedViewApi): DashboardListSavedView {
    return {
        ...view,
        filters: { ...DEFAULT_FILTERS, ...view.filters },
        scope: view.scope ?? 'private',
    }
}

function savedViewsPage(
    response: Awaited<ReturnType<typeof api.dashboardSavedViewsList>>,
    scope: DashboardSavedViewScope
): DashboardSavedViewsPage {
    return {
        views: response.results.map(dashboardListSavedView),
        nextCursor: response.next ? new URL(response.next).searchParams.get('cursor') : null,
        scope,
    }
}

export async function loadDashboardSavedViews(
    teamId: number,
    scope: DashboardSavedViewScope,
    cursor?: string
): Promise<DashboardSavedViewsPage> {
    return savedViewsPage(await api.dashboardSavedViewsList(String(teamId), { limit: 100, scope, cursor }), scope)
}

export const dashboardSavedViewsLogic = kea<dashboardSavedViewsLogicType>([
    props({} as DashboardSavedViewsLogicProps),
    key((props) => props.teamId ?? 'no-team'),
    path((key) => ['products', 'dashboards', 'saved-views', 'dashboardSavedViewsLogic', key]),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], dashboardsLogic, ['currentTab', 'filters']],
        actions: [featureFlagLogic, ['setFeatureFlags'], dashboardsLogic, ['setCurrentTab', 'setFilters', 'setSearch']],
    })),
    actions({
        loadSavedViews: true,
        loadSavedViewsSuccess: (pages: DashboardSavedViewsPage[]) => ({ pages }),
        loadSavedViewsFailure: (message: string, errorObject: unknown) => ({ message, errorObject }),
        loadMoreSavedViews: (scope: DashboardSavedViewScope) => ({ scope }),
        loadMoreSavedViewsSuccess: (page: DashboardSavedViewsPage) => ({ page }),
        loadMoreSavedViewsFailure: (message: string, errorObject: unknown) => ({ message, errorObject }),
        savedViewCreated: (view: DashboardListSavedView) => ({ view }),
        savedViewUpdated: (view: DashboardListSavedView) => ({ view }),
        savedViewDeleted: (id: string) => ({ id }),
        setActiveSavedViewId: (id: string | null) => ({ id }),
    }),
    reducers(() => ({
        activeSavedViewId: [
            null as string | null,
            buildUserScopedPersistenceConfig('dashboard_list_saved_view__'),
            {
                setActiveSavedViewId: (_, { id }) => id,
                savedViewDeleted: (activeSavedViewId, { id }) => {
                    if (activeSavedViewId === id) {
                        return null
                    }
                    return activeSavedViewId
                },
            },
        ],
        savedViewsAvailable: [
            true,
            {
                loadSavedViewsSuccess: () => true,
                loadSavedViewsFailure: (_, { errorObject }) => !isSavedViewsUnavailableError(errorObject),
            },
        ],
        savedViewsNextCursors: [
            emptySavedViewCursors,
            {
                loadSavedViews: () => emptySavedViewCursors,
                loadSavedViewsSuccess: (_, { pages }) => ({
                    private: pages.find((page) => page.scope === 'private')?.nextCursor ?? null,
                    team: pages.find((page) => page.scope === 'team')?.nextCursor ?? null,
                }),
                loadMoreSavedViewsSuccess: (cursors, { page }) => ({
                    ...cursors,
                    [page.scope]: page.nextCursor,
                }),
            },
        ],
        savedViewsLoadError: [
            false,
            {
                loadSavedViews: () => false,
                loadSavedViewsFailure: (_, { errorObject }) => !isSavedViewsUnavailableError(errorObject),
                loadSavedViewsSuccess: () => false,
            },
        ],
        savedViewsLoadMoreFailed: [
            false,
            {
                loadSavedViews: () => false,
                loadMoreSavedViews: () => false,
                loadMoreSavedViewsFailure: () => true,
                loadMoreSavedViewsSuccess: () => false,
            },
        ],
        savedViewsLoading: [
            false,
            { loadSavedViews: () => true, loadSavedViewsFailure: () => false, loadSavedViewsSuccess: () => false },
        ],
        loadMoreSavedViewsLoading: [
            false,
            {
                loadMoreSavedViews: () => true,
                loadMoreSavedViewsFailure: () => false,
                loadMoreSavedViewsSuccess: () => false,
            },
        ],
        savedViews: [
            [] as DashboardListSavedView[],
            {
                loadSavedViews: () => [],
                loadSavedViewsSuccess: (_, { pages }) => pages.flatMap((page) => page.views),
                loadMoreSavedViewsSuccess: (views, { page }) => {
                    const ids = new Set(views.map((view) => view.id))
                    return [...views, ...page.views.filter((view) => !ids.has(view.id))]
                },
                savedViewCreated: (views, { view }) => [...views, view],
                savedViewUpdated: (views, { view }) => views.map((item) => (item.id === view.id ? view : item)),
                savedViewDeleted: (views, { id }) => views.filter((view) => view.id !== id),
            },
        ],
    })),
    selectors(({ props }) => ({
        dashboardSavedViewsEnabled: [
            (selectors) => [selectors.featureFlags, selectors.savedViewsAvailable],
            (featureFlags: FeatureFlagsSet, savedViewsAvailable: boolean): boolean =>
                props.teamId != null && !!featureFlags[FEATURE_FLAGS.DASHBOARD_SAVED_VIEWS] && savedViewsAvailable,
        ],
    })),
    listeners(({ actions, props, values }) => ({
        loadSavedViewsSuccess: ({ pages }) => {
            const views = pages.flatMap((page) => page.views)
            if (values.activeSavedViewId && views.some((view) => view.id === values.activeSavedViewId)) {
                return
            }
            actions.setActiveSavedViewId(views.find((view) => isEqual(view.filters, values.filters))?.id ?? null)
        },
        setFilters: async (_, breakpoint) => {
            await breakpoint(0)
            if (!hasDashboardFilters(dashboardsLogic.values.filters)) {
                actions.setActiveSavedViewId(null)
            }
        },
        setSearch: async (_, breakpoint) => {
            await breakpoint(0)
            if (!hasDashboardFilters(dashboardsLogic.values.filters)) {
                actions.setActiveSavedViewId(null)
            }
        },
        setFeatureFlags: () => {
            if (values.dashboardSavedViewsEnabled && !values.savedViewsLoading) {
                if (values.currentTab === DashboardsTab.Pinned) {
                    actions.setCurrentTab(DashboardsTab.All)
                    actions.setFilters({ pinned: true })
                }
                actions.loadSavedViews()
            }
        },
        loadSavedViews: async (_, breakpoint) => {
            if (props.teamId == null) {
                actions.loadSavedViewsSuccess([])
                return
            }
            try {
                const pages = await Promise.all([
                    loadDashboardSavedViews(props.teamId, 'private'),
                    loadDashboardSavedViews(props.teamId, 'team'),
                ])
                breakpoint()
                actions.loadSavedViewsSuccess(pages)
            } catch (error) {
                if (!isSavedViewsUnavailableError(error)) {
                    posthog.captureException(error)
                }
                actions.loadSavedViewsFailure(
                    error instanceof Error ? error.message : 'Could not load saved views',
                    error
                )
            }
        },
        loadMoreSavedViews: async ({ scope }, breakpoint) => {
            const cursor = values.savedViewsNextCursors[scope]
            if (props.teamId == null || cursor == null) {
                return
            }
            try {
                const page = await loadDashboardSavedViews(props.teamId, scope, cursor)
                breakpoint()
                actions.loadMoreSavedViewsSuccess(page)
            } catch (error) {
                if (!isSavedViewsUnavailableError(error)) {
                    posthog.captureException(error)
                }
                actions.loadMoreSavedViewsFailure(
                    error instanceof Error ? error.message : 'Could not load more saved views',
                    error
                )
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.dashboardSavedViewsEnabled) {
            actions.loadSavedViews()
        }
    }),
])
