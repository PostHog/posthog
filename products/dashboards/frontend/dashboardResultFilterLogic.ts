export const dashboardResultFilterLogic: LogicWrapper<dashboardResultFilterLogicType> =
    kea<dashboardResultFilterLogicType>([
        props({} as DashboardResultFilterProps),
        key((props: DashboardResultFilterProps) => props.dashboardId),
        path((key) => ['products', 'dashboards', 'dashboardResultFilterLogic', key]),
        actions({
            selectResult: (selection: DashboardResultSelection) => ({ selection }),
            setSelection: (selection: DashboardResultSelection | null) => ({ selection }),
            restoreFromUrl: true,
        }),
        reducers({
            selection: [null as DashboardResultSelection | null, { setSelection: (_, { selection }) => selection }],
        }),
        selectors({
            loadQueue: [() => [(_, props) => props.loadQueue], (loadQueue: TaskQueue | undefined) => loadQueue],
            targets: [
                (s) => [s.selection, (_, props) => props.tiles],
                (selection: DashboardResultSelection | null, tiles: DashboardTile[] | undefined) =>
                    getDashboardResultTargets(tiles ?? [], selection),
            ],
            sourceInsight: [
                (s) => [s.selection, (_, props) => props.tiles],
                (selection: DashboardResultSelection | null, tiles: DashboardTile[] | undefined) =>
                    tiles?.find((tile) => tile.id === selection?.tileId)?.insight,
            ],
        }),
        listeners(({ actions, values, props }) => ({
            selectResult: ({ selection }) => {
                const same =
                    values.selection?.tileId === selection.tileId && deepEqual(values.selection.query, selection.query)
                actions.setSelection(same ? null : selection)
            },
            setSelection: ({ selection }) => {
                const location = router.values.currentLocation
                if (selection) {
                    const hash = { ...location.hashParams }
                    hash.insight_filter = JSON.stringify(selection)
                    delete hash.bi_filter
                    router.actions.replace(location.pathname, location.searchParams, hash)
                } else {
                    if (
                        readDashboardResultFilter(location.hashParams.insight_filter)?.dashboardId === props.dashboardId
                    ) {
                        const hash = { ...location.hashParams }
                        delete hash.insight_filter
                        router.actions.replace(location.pathname, location.searchParams, hash)
                    }
                }
            },
            restoreFromUrl: () => {
                const selection = router.values.currentLocation.hashParams.bi_filter
                    ? null
                    : readDashboardResultFilter(router.values.currentLocation.hashParams.insight_filter)
                if (!selection && values.selection) {
                    actions.setSelection(null)
                } else if (
                    selection?.dashboardId === props.dashboardId &&
                    props.tiles?.some((tile) => tile.id === selection.tileId) &&
                    !deepEqual(selection, values.selection)
                ) {
                    actions.setSelection(selection)
                }
            },
        })),
        urlToAction(({ actions }) => ({ ['/dashboard/:id']: () => actions.restoreFromUrl() })),
        afterMount(({ actions }) => actions.restoreFromUrl()),
        propsChanged(({ actions, values, props }, oldProps) => {
            const selection = values.selection
            if (selection && props.tiles && oldProps.tiles) {
                const source = props.tiles.find((tile) => tile.id === selection.tileId)
                const previous = oldProps.tiles.find((tile) => tile.id === selection.tileId)
                if (!source || (previous && !deepEqual(source.insight?.query, previous.insight?.query))) {
                    actions.setSelection(null)
                }
                const previousTiles = new Map(oldProps.tiles.map((tile) => [tile.id, tile]))
                for (const tile of props.tiles) {
                    const target = values.targets[tile.id]
                    const oldTile = previousTiles.get(tile.id)
                    if (!target || !oldTile || tile.insight?.last_refresh === oldTile.insight?.last_refresh) {
                        continue
                    }
                    const logic = dataNodeLogic.findMounted({
                        key: insightVizDataNodeKey({
                            dashboardItemId: getDashboardResultItemId(props.dashboardId, tile.id),
                        }),
                    })
                    if (logic && deepEqual(logic.props.query, target.source)) {
                        logic.actions.loadData('force_blocking')
                    }
                }
            }
            actions.restoreFromUrl()
        }),
    ])
