type DashboardByProduct = (typeof dashboards)[number]

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardsByProductLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    starredProductIds: Record<string, string> // navProductsTabLogic
    visibleDashboards: DashboardByProduct[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardsByProductLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        visibleDashboards: (
            featureFlags: FeatureFlagsSet,
            starredProductIds: Record<string, string>
        ) => DashboardByProduct[]
    }
}

export type dashboardsByProductLogicType = MakeLogicType<
    dashboardsByProductLogicValues,
    {},
    Record<string, any>,
    dashboardsByProductLogicMeta
>

export const dashboardsByProductLogic = kea<dashboardsByProductLogicType>([
    path(['products', 'dashboards', 'dashboardsByProductLogic']),
    connect({ values: [featureFlagLogic, ['featureFlags'], navProductsTabLogic, ['starredProductIds']] }),
    selectors({
        visibleDashboards: [
            (s) => [s.featureFlags, s.starredProductIds],
            (featureFlags: FeatureFlagsSet, starredProductIds: Record<string, string>): DashboardByProduct[] => {
                const flag = featureFlags[FEATURE_FLAGS.PRODUCT_ANALYTICS_HOME_TAB]
                const showProductAnalytics = flag === true || flag === 'test'
                return dashboards
                    .filter((dashboard) => dashboard.key !== 'product' || showProductAnalytics)
                    .sort(
                        (a, b) =>
                            Number(!!starredProductIds[b.sidebarPath]) - Number(!!starredProductIds[a.sidebarPath])
                    )
            },
        ],
    }),
    afterMount(() => {
        const flag = featureFlagLogic.values.featureFlags[FEATURE_FLAGS.DASHBOARDS_BY_PRODUCT]
        if (flag === true || flag === 'test') {
            eventUsageLogic.actions.reportDashboardsByProductViewed()
        }
    }),
])
