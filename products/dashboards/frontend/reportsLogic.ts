export const reportsLogic: LogicWrapper<reportsLogicType> = kea<reportsLogicType>([
    props({} as ReportsLogicProps),
    key(({ folder, teamId }) => `${teamId ?? getCurrentTeamIdOrNone()}:${folder}`),
    path((key) => ['products', 'dashboards', 'frontend', 'reportsLogic', key]),
    connect((props: ReportsLogicProps) => ({
        values: [
            newDashboardLogic,
            ['isLoading as dashboardCreationLoading'],
            teamLogic,
            ['currentTeamId'],
            projectTreeDataLogic,
            ['viableItems', 'folderStates'],
            projectTreeLogic(reportsTreeProps(props.folder, props.teamId)),
            ['fullFileSystemFiltered', 'searchTerm', 'searchResultsLoading', 'searchResults'],
        ],
        actions: [
            newDashboardLogic,
            ['addDashboard', 'setAsHomeTabDashboardAfterCreation', 'setRedirectAfterCreation'],
            projectTreeDataLogic,
            ['setLastNewFolder', 'loadFolder', 'loadFolderSuccess'],
            projectTreeLogic(reportsTreeProps(props.folder, props.teamId)),
            ['setSearchTerm', 'loadSearchResults'],
        ],
    })),
    actions({
        createDashboard: true,
        createInsight: true,
        openFolderSetup: (teamFolder = true, entry: FileSystemEntry | null = null) => ({ teamFolder, entry }),
        closeFolderSetup: true,
        setFileType: (fileType: string) => ({ fileType }),
        pinDashboard: (dashboardId: number | null) => ({ dashboardId }),
    }),
    forms(({ actions, values, props }) => ({
        folderForm: {
            defaults: { name: '', description: '', teamFolder: true, dashboardId: null as number | null },
            errors: ({ name }) => ({
                name: !name.trim()
                    ? 'Give the folder a name'
                    : !values.editingFolder &&
                        values.viableItems.some(
                            (item) =>
                                item.type === 'folder' &&
                                item.path === joinPath([...splitPath(props.folder), name.trim()])
                        )
                      ? 'A folder with this name already exists'
                      : undefined,
            }),
            submit: async ({ name, description, teamFolder, dashboardId }) => {
                const teamId = props.teamId ?? values.currentTeamId
                if (!teamId) {
                    throw new Error('Select a project before creating a folder')
                }
                const context = {
                    team_folder: teamFolder,
                    description: description.trim(),
                    pinned_dashboard_id: dashboardId,
                }
                const entry = values.editingFolder
                const folder = entry?.path ?? joinPath([...splitPath(props.folder), name.trim()])
                const meta = { ...entry?.meta, custom_dashboards: context }
                if (entry) {
                    await fileSystemPartialUpdate(String(teamId), entry.id, { meta })
                } else {
                    await fileSystemCreate(String(teamId), { path: folder, type: 'folder', meta })
                }
                actions.loadFolder(parentPath(folder), true)
                actions.closeFolderSetup()
                if (!entry) {
                    router.actions.push(urls.reports(folder))
                }
            },
        },
    })),
    loaders(({ actions, values, props }) => ({
        availableDashboards: [
            [] as DashboardBasicApi[],
            {
                loadDashboards: async (): Promise<DashboardBasicApi[]> => {
                    const teamId = props.teamId ?? values.currentTeamId ?? getCurrentTeamIdOrNone()
                    if (!teamId) {
                        throw new Error('Select a project before loading dashboards')
                    }
                    const results: DashboardBasicApi[] = []
                    let hasMore = true
                    while (hasMore) {
                        const page = await dashboardsList(String(teamId), {
                            limit: 1000,
                            offset: results.length,
                            exclude_generated: true,
                        })
                        results.push(...page.results)
                        hasMore = !!page.next && page.results.length > 0
                    }
                    return results
                },
            },
        ],
        savedContext: [
            null as number | null,
            {
                savePinnedDashboard: async ({ dashboardId }: { dashboardId: number | null }) => {
                    const entry = values.currentFolder
                    const teamId = props.teamId ?? values.currentTeamId
                    if (!entry || !teamId) {
                        throw new Error('Reload the folder before pinning a dashboard')
                    }
                    await fileSystemPartialUpdate(String(teamId), entry.id, {
                        meta: {
                            ...entry.meta,
                            custom_dashboards: { ...getReportFolderContext(entry), pinned_dashboard_id: dashboardId },
                        },
                    })
                    actions.loadFolder(parentPath(props.folder), true)
                    return dashboardId
                },
            },
        ],
    })),
    reducers({
        folderSetupOpen: [false, { openFolderSetup: () => true, closeFolderSetup: () => false }],
        editingFolder: [
            null as FileSystemEntry | null,
            { openFolderSetup: (_, { entry }) => entry, closeFolderSetup: () => null },
        ],
        fileType: ['all', { setFileType: (_, { fileType }) => fileType }],
        loadDashboardsFailed: [false, { loadDashboardsSuccess: () => false, loadDashboardsFailure: () => true }],
    }),
    selectors({
        nameSortedDashboards: [
            (s) => [s.availableDashboards],
            (dashboards: DashboardBasicApi[]): DashboardBasicApi[] =>
                dashboards
                    .filter(
                        (dashboard) =>
                            !dashboard.deleted &&
                            !getEntryAccessDisabledReason({
                                type: 'dashboard',
                                user_access_level: dashboard.user_access_level,
                            })
                    )
                    .sort((a, b) => (a.name ?? '').localeCompare(b.name ?? '')),
        ],
        dashboardsLoading: [(s) => [s.availableDashboardsLoading], (loading: boolean): boolean => loading],

        currentFolder: [
            (s) => [s.viableItems, (_, props) => props.folder],
            (items: FileSystemEntry[], folder: string): FileSystemEntry | undefined =>
                items.find((item) => item.type === 'folder' && item.path === folder),
        ],
        folderContext: [
            (s) => [s.currentFolder],
            (folder: FileSystemEntry | undefined) => getReportFolderContext(folder),
        ],
        pinnedDashboard: [
            (s) => [s.folderContext, s.nameSortedDashboards],
            (context: ReportFolderContext, dashboards: DashboardBasicApi[]) =>
                dashboards.find((dashboard) => dashboard.id === context.pinned_dashboard_id),
        ],
        entries: [
            (s) => [s.fullFileSystemFiltered, s.searchTerm, s.viableItems, (_, props) => props.folder],
            (
                items: TreeDataItem[],
                search: string,
                loadedItems: FileSystemEntry[],
                folder: string
            ): FileSystemEntry[] => {
                if (!search) {
                    return loadedItems.filter((entry) => parentPath(entry.path) === folder)
                }
                const flatten = (rows: TreeDataItem[]): FileSystemEntry[] =>
                    rows.flatMap((row) => [
                        ...(row.record?.id && row.type !== 'loading-indicator' && row.type !== 'empty-folder'
                            ? [row.record as FileSystemEntry]
                            : []),
                        ...(search && row.children ? flatten(row.children) : []),
                    ])
                return flatten(items)
            },
        ],
        folderEntries: [
            (s) => [s.entries],
            (entries: FileSystemEntry[]): FileSystemEntry[] =>
                entries.filter((entry) => entry.type === 'folder').sort((a, b) => a.path.localeCompare(b.path)),
        ],
        fileEntries: [
            (s) => [s.entries, s.fileType],
            (entries: FileSystemEntry[], type: string): FileSystemEntry[] =>
                entries.filter((entry) => entry.type !== 'folder' && (type === 'all' || entry.type === type)),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        loadFolderSuccess: ({ folder, hasMore }) => {
            if (props.folder && folder === parentPath(props.folder) && hasMore && !values.currentFolder) {
                actions.loadFolder(folder)
            }
        },
        openFolderSetup: ({ teamFolder, entry }) => {
            const context = getReportFolderContext(entry ?? undefined)
            actions.resetFolderForm({
                name: entry ? (splitPath(entry.path).at(-1) ?? '') : '',
                description: context.description,
                teamFolder: entry ? context.team_folder : teamFolder,
                dashboardId: context.pinned_dashboard_id,
            })
        },
        pinDashboard: ({ dashboardId }) => {
            if (!values.savedContextLoading && !values.isFolderFormSubmitting) {
                actions.savePinnedDashboard({ dashboardId })
            }
        },
        savePinnedDashboardFailure: () => {
            lemonToast.error('Could not pin the dashboard. Try again.')
        },
        submitFolderFormFailure: () => {
            lemonToast.error('Could not save the folder. Your changes are still here. Try again.')
        },
        createDashboard: () => {
            if (values.dashboardCreationLoading) {
                return
            }
            actions.setAsHomeTabDashboardAfterCreation(false)
            actions.setRedirectAfterCreation(true)
            actions.addDashboard({ name: 'New dashboard', _create_in_folder: props.folder, show: true })
        },
        createInsight: () => {
            actions.setLastNewFolder(props.folder)
            router.actions.push(urls.insightNew())
        },
    })),
    afterMount(({ actions, props }) => {
        actions.loadFolder(props.folder)
        if (props.folder) {
            actions.loadFolder(parentPath(props.folder))
        }
        actions.loadDashboards()
    }),
])
