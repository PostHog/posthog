/**
 * The project-wide ReviewHog settings: which repositories of each GitHub installation this project
 * reviews, the rule for automatic Flash with its people lists, bot pull requests, and the project
 * defaults for Full reviews. Members read them; only project admins can change them (`can_edit`).
 */
export const reviewHogProjectSettingsLogic = kea<reviewHogProjectSettingsLogicType>([
    path(['products', 'review_hog', 'frontend', 'repositories', 'reviewHogProjectSettingsLogic']),

    connect(() => ({
        actions: [reviewHogSettingsLogic, ['loadSettings']],
    })),

    actions({
        // Asks for a confirm first when the change removes repositories from this project.
        changeClaimScope: (installation: ReviewInstallationApi, scope: ClaimScopeChoice) => ({ installation, scope }),
        setClaimScope: (installation: ReviewInstallationApi, scope: ClaimScopeChoice) => ({ installation, scope }),
        setClaimScopeFinished: true,
    }),

    loaders(() => ({
        projectSettings: [
            null as ReviewProjectSettingsApi | null,
            {
                loadProjectSettings: async () => await reviewHogProjectSettingsRetrieve(currentProjectId()),
                updateProjectSettings: async (patch: PatchedReviewProjectSettingsApi) =>
                    await reviewHogProjectSettingsPartialUpdate(currentProjectId(), patch),
                addProjectPerson: async ({
                    userId,
                    kind,
                }: {
                    userId: number
                    kind: ReviewRepositoryPersonKindEnumApi
                }) => await reviewHogProjectSettingsPeopleCreate(currentProjectId(), { user_id: userId, kind }),
                removeProjectPerson: async (person: ReviewRepositoryPersonApi) =>
                    await reviewHogProjectSettingsPeopleDestroy(currentProjectId(), person.id),
            },
        ],
    })),

    reducers({
        claimSaving: [
            false,
            {
                setClaimScope: () => true,
                setClaimScopeFinished: () => false,
            },
        ],
        projectSettingsLoadFailed: [
            false,
            {
                loadProjectSettings: () => false,
                loadProjectSettingsSuccess: () => false,
                loadProjectSettingsFailure: () => true,
            },
        ],
    }),

    selectors({
        canEdit: [
            (s) => [s.projectSettings],
            (projectSettings: ReviewProjectSettingsApi | null): boolean => projectSettings?.can_edit ?? false,
        ],
        installations: [
            (s) => [s.projectSettings],
            (projectSettings: ReviewProjectSettingsApi | null): readonly ReviewInstallationApi[] =>
                projectSettings?.installations ?? [],
        ],
        editDisabledReason: [
            (s) => [s.projectSettings, s.projectSettingsLoading],
            (projectSettings: ReviewProjectSettingsApi | null, loading: boolean): string | undefined => {
                if (projectSettings === null) {
                    return 'Loading…'
                }
                if (!projectSettings.can_edit) {
                    return 'Only project admins can change this'
                }
                return loading ? 'Saving…' : undefined
            },
        ],
    }),

    listeners(({ actions }) => ({
        changeClaimScope: async ({ installation, scope }) => {
            const account = installation.account_name
            if (scope === (installation.scope ?? 'none')) {
                return
            }
            if (scope === 'none') {
                LemonDialog.open({
                    title: `Stop reviewing ${account} here?`,
                    description:
                        'This project stops reviewing every repository of this GitHub account. Its selected repositories and exceptions there are removed. Personal choices stay.',
                    primaryButton: {
                        children: 'Stop reviewing',
                        status: 'danger',
                        onClick: () => actions.setClaimScope(installation, scope),
                        'data-attr': 'review-hog-claim-remove-confirm',
                    },
                    secondaryButton: { children: 'Cancel' },
                })
                return
            }
            if (scope === 'selected' && installation.scope === 'all') {
                let leaving: number | null = null
                try {
                    leaving = await countRepositoriesLeaving(installation.installation_id)
                } catch {
                    // The confirm still explains the change without the number.
                }
                const count =
                    leaving === null
                        ? 'Repositories that are not selected'
                        : `${leaving} ${leaving === 1 ? 'repository' : 'repositories'}`
                LemonDialog.open({
                    title: 'Review only selected repositories?',
                    description: `${count} stop being reviewed here, and their exceptions are removed. New repositories of ${account} are not reviewed until you include them. Personal choices stay.`,
                    primaryButton: {
                        children: 'Only selected repositories',
                        onClick: () => actions.setClaimScope(installation, scope),
                        'data-attr': 'review-hog-claim-selected-confirm',
                    },
                    secondaryButton: { children: 'Cancel' },
                })
                return
            }
            actions.setClaimScope(installation, scope)
        },
        setClaimScope: async ({ installation, scope }) => {
            try {
                if (scope === 'none') {
                    if (installation.claim_id) {
                        await reviewHogInstallationClaimsDestroy(currentProjectId(), installation.claim_id)
                    }
                } else if (installation.claim_id) {
                    await reviewHogInstallationClaimsPartialUpdate(currentProjectId(), installation.claim_id, { scope })
                } else {
                    await reviewHogInstallationClaimsCreate(currentProjectId(), {
                        installation_id: installation.installation_id,
                        scope,
                    })
                }
                // pinned: analytics event names in this file feed the Code review usage dashboards
                posthog.capture('review hog installation claim changed', {
                    scope,
                    previous_scope: installation.scope ?? 'none',
                })
            } catch (error) {
                lemonToast.error(errorMessage(error, 'Could not save the change. Try again.'))
            }
            actions.setClaimScopeFinished()
            actions.loadProjectSettings()
        },
        updateProjectSettingsSuccess: ({ payload }) => {
            if (payload?.flash_for !== undefined) {
                posthog.capture('review hog project rule changed', { flash_for: payload.flash_for })
            }
            if (payload?.bot_prs !== undefined) {
                posthog.capture('review hog bot pull requests changed', { bot_prs: payload.bot_prs })
            }
            for (const key of ['urgency_threshold', 'celebrate_clean_reviews'] as const) {
                if (payload?.[key] !== undefined) {
                    posthog.capture('review hog project default changed', { key, value: payload[key] })
                    // Everyone without an own value now gets the new default.
                    actions.loadSettings()
                }
            }
        },
        addProjectPersonSuccess: ({ payload }) => {
            posthog.capture('review hog project person added', { kind: payload?.kind })
        },
        removeProjectPersonSuccess: ({ payload }) => {
            posthog.capture('review hog project person removed', { kind: payload?.kind })
        },
        updateProjectSettingsFailure: () => {
            // The loaders toast already showed the error. Reload so the controls show what is saved.
            actions.loadProjectSettings()
        },
    })),

    afterMount(({ actions }) => {
        actions.loadProjectSettings()
    }),
])
