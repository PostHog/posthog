/**
 * The repository list of the Code review settings: every repository a connected GitHub installation
 * can see, joined with this project's settings and the viewer's own choices. The server decides
 * `my_result` and `inherited_result`, so every write reloads the page instead of computing a rule here.
 */
export const reviewHogRepositoriesLogic = kea<reviewHogRepositoriesLogicType>([
    path(['products', 'review_hog', 'frontend', 'repositories', 'reviewHogRepositoriesLogic']),

    connect(() => ({
        values: [
            reviewHogProjectSettingsLogic,
            ['projectSettings', 'installations', 'canEdit'],
            teamLogic,
            ['currentTeamId'],
        ],
        actions: [
            reviewHogProjectSettingsLogic,
            [
                'loadProjectSettings',
                'loadProjectSettingsSuccess',
                'updateProjectSettingsSuccess',
                'addProjectPersonSuccess',
                'removeProjectPersonSuccess',
            ],
            reviewHogSettingsLogic,
            ['updateSettings', 'updateSettingsSuccess'],
        ],
    })),

    actions({
        selectInstallation: (installationId: string) => ({ installationId }),
        setSearch: (search: string) => ({ search }),
        setView: (view: ReviewHogRepositoryOverviewRetrieveView) => ({ view }),
        setPage: (page: number) => ({ page }),
        includeRepository: (entry: ReviewRepositoryOverviewEntryApi) => ({ entry }),
        removeFromProject: (entry: ReviewRepositoryOverviewEntryApi) => ({ entry }),
        addException: (entry: ReviewRepositoryOverviewEntryApi) => ({ entry }),
        clearException: (entry: ReviewRepositoryOverviewEntryApi) => ({ entry }),
        setExceptionFlashFor: (entry: ReviewRepositoryOverviewEntryApi, flashFor: AutomaticFlashForEnumApi) => ({
            entry,
            flashFor,
        }),
        addExceptionPerson: (
            entry: ReviewRepositoryOverviewEntryApi,
            userId: number,
            kind: ReviewRepositoryPersonKindEnumApi
        ) => ({ entry, userId, kind }),
        removeExceptionPerson: (entry: ReviewRepositoryOverviewEntryApi, person: ReviewRepositoryPersonApi) => ({
            entry,
            person,
        }),
        setMyChoice: (entry: ReviewRepositoryOverviewEntryApi, value: MyChoiceValue) => ({ entry, value }),
        setMyDefault: (mode: DefaultReviewModeEnumApi) => ({ mode }),
        // One write per repository at a time. The row shows it as saving until the page reloads.
        repositorySaveStarted: (fullName: string) => ({ fullName }),
        repositorySaveFinished: (fullName: string) => ({ fullName }),
    }),

    loaders(({ values }) => ({
        overview: [
            null as ReviewRepositoryOverviewApi | null,
            {
                loadOverview: async (_: void, breakpoint) => {
                    const installationId = values.installation?.installation_id
                    if (!installationId) {
                        return null
                    }
                    const overview = await reviewHogRepositoryOverviewRetrieve(currentProjectId(), {
                        installation_id: installationId,
                        search: values.search.trim() || undefined,
                        view: values.view,
                        offset: values.page * REPOSITORIES_PAGE_SIZE,
                        limit: REPOSITORIES_PAGE_SIZE,
                    })
                    breakpoint()
                    return overview
                },
            },
        ],
    })),

    reducers({
        selectedInstallationId: [
            null as string | null,
            {
                selectInstallation: (_, { installationId }) => installationId,
            },
        ],
        search: [
            '',
            {
                setSearch: (_, { search }) => search,
            },
        ],
        view: [
            ReviewHogRepositoryOverviewRetrieveView.All as ReviewHogRepositoryOverviewRetrieveView,
            {
                setView: (_, { view }) => view,
            },
        ],
        page: [
            0,
            {
                setPage: (_, { page }) => page,
                setSearch: () => 0,
                setView: () => 0,
                selectInstallation: () => 0,
            },
        ],
        overviewLoadFailed: [
            false,
            {
                loadOverview: () => false,
                loadOverviewSuccess: () => false,
                loadOverviewFailure: () => true,
            },
        ],
        busyRepositories: [
            [] as string[],
            {
                repositorySaveStarted: (state, { fullName }) => [...state, fullName],
                repositorySaveFinished: (state, { fullName }) => state.filter((name) => name !== fullName),
            },
        ],
    }),

    selectors({
        installation: [
            (s) => [s.installations, s.selectedInstallationId],
            (
                installations: readonly ReviewInstallationApi[],
                selectedInstallationId: string | null
            ): ReviewInstallationApi | null =>
                installations.find((installation) => installation.installation_id === selectedInstallationId) ??
                installations[0] ??
                null,
        ],
        pageCount: [
            (s) => [s.overview],
            (overview: ReviewRepositoryOverviewApi | null): number =>
                Math.max(1, Math.ceil((overview?.total ?? 0) / REPOSITORIES_PAGE_SIZE)),
        ],
        // Back to the Settings tab after GitHub authorizes, so the user lands on the claim picker.
        connectGitHubUrl: [
            (s) => [s.currentTeamId],
            (currentTeamId: number | null): string =>
                `${getIntegrationsAuthorizeRetrieveUrl(String(currentTeamId))}?${new URLSearchParams({
                    kind: 'github',
                    next: combineUrl(urls.codeReview(), { tab: 'settings' }).url,
                })}`,
        ],
    }),

    listeners(({ actions, values }) => {
        /** Runs one write for a repository, then reloads the page so every result comes from the server. */
        async function writeRepository(
            entry: ReviewRepositoryOverviewEntryApi,
            write: () => Promise<void>,
            fallbackError: string
        ): Promise<boolean> {
            if (values.busyRepositories.includes(entry.full_name)) {
                return false
            }
            actions.repositorySaveStarted(entry.full_name)
            let saved = false
            try {
                await write()
                saved = true
            } catch (error) {
                lemonToast.error(errorMessage(error, fallbackError))
            }
            actions.repositorySaveFinished(entry.full_name)
            actions.loadOverview()
            return saved
        }

        function repositoryRef(entry: ReviewRepositoryOverviewEntryApi): {
            installation_id: string
            full_name: string
            github_repo_id?: number
        } {
            return {
                installation_id: values.installation?.installation_id ?? '',
                full_name: entry.full_name,
                github_repo_id: entry.github_repo_id ?? undefined,
            }
        }

        return {
            selectInstallation: () => actions.loadOverview(),
            setSearch: async (_, breakpoint) => {
                // Typing in the filter fires one request per pause, not per key.
                await breakpoint(300)
                actions.loadOverview()
            },
            setView: () => actions.loadOverview(),
            setPage: () => actions.loadOverview(),
            // A write can empty the last page. Go to the last page that still has rows.
            loadOverviewSuccess: ({ overview }) => {
                if (overview && values.page >= values.pageCount) {
                    actions.setPage(values.pageCount - 1)
                }
            },
            // A first include creates a claim, and the rule or a list change can change every result.
            loadProjectSettingsSuccess: () => actions.loadOverview(),
            updateProjectSettingsSuccess: () => actions.loadOverview(),
            addProjectPersonSuccess: () => actions.loadOverview(),
            removeProjectPersonSuccess: () => actions.loadOverview(),
            includeRepository: async ({ entry }) => {
                const saved = await writeRepository(
                    entry,
                    async () => {
                        const response = await reviewHogRepositoriesCreate(currentProjectId(), {
                            ...repositoryRef(entry),
                            selected: true,
                        })
                        if (response.taken_from_project) {
                            lemonToast.info(`${entry.full_name} is now reviewed here instead of in the other project.`)
                        }
                    },
                    'Could not include the repository. Try again.'
                )
                if (saved) {
                    // pinned: analytics event names in this file feed the Code review usage dashboards
                    posthog.capture('review hog repository included', { taken: entry.owner === 'other_project' })
                    actions.loadProjectSettings()
                }
            },
            removeFromProject: async ({ entry }) => {
                const saved = await writeRepository(
                    entry,
                    async () => {
                        await reviewHogRepositoriesCreate(currentProjectId(), {
                            ...repositoryRef(entry),
                            selected: false,
                        })
                    },
                    'Could not remove the repository. Try again.'
                )
                if (saved) {
                    posthog.capture('review hog repository removed')
                }
            },
            addException: async ({ entry }) => {
                const project = values.projectSettings
                const flashFor = project?.flash_for ?? 'off'
                const kind = peopleKindFor(flashFor)
                const people = kind ? (project?.people ?? []).filter((person) => person.kind === kind) : []
                const saved = await writeRepository(
                    entry,
                    async () => {
                        // The exception starts as a copy of the project rule, so adding it changes nothing yet.
                        const response = await reviewHogRepositoriesCreate(currentProjectId(), {
                            ...repositoryRef(entry),
                            flash_for: flashFor,
                        })
                        const repositoryId = response.repository?.id
                        if (repositoryId && kind) {
                            for (const person of people) {
                                await reviewHogRepositoriesPeopleCreate(currentProjectId(), repositoryId, {
                                    user_id: person.user.id,
                                    kind,
                                })
                            }
                        }
                    },
                    'Could not add the exception. Try again.'
                )
                if (saved) {
                    posthog.capture('review hog repository exception added', { flash_for: flashFor })
                }
            },
            clearException: async ({ entry }) => {
                const saved = await writeRepository(
                    entry,
                    async () => {
                        await reviewHogRepositoriesCreate(currentProjectId(), {
                            ...repositoryRef(entry),
                            flash_for: null,
                        })
                    },
                    'Could not clear the exception. Try again.'
                )
                if (saved) {
                    posthog.capture('review hog repository exception cleared')
                }
            },
            setExceptionFlashFor: async ({ entry, flashFor }) => {
                const saved = await writeRepository(
                    entry,
                    async () => {
                        await reviewHogRepositoriesCreate(currentProjectId(), {
                            ...repositoryRef(entry),
                            flash_for: flashFor,
                        })
                    },
                    'Could not save the exception. Try again.'
                )
                if (saved) {
                    posthog.capture('review hog repository exception changed', { flash_for: flashFor })
                }
            },
            addExceptionPerson: async ({ entry, userId, kind }) => {
                const repositoryId = entry.repository_id
                if (!repositoryId) {
                    return
                }
                const saved = await writeRepository(
                    entry,
                    async () => {
                        await reviewHogRepositoriesPeopleCreate(currentProjectId(), repositoryId, {
                            user_id: userId,
                            kind,
                        })
                    },
                    'Could not add the person. Try again.'
                )
                if (saved) {
                    posthog.capture('review hog repository person added', { kind })
                }
            },
            removeExceptionPerson: async ({ entry, person }) => {
                const repositoryId = entry.repository_id
                if (!repositoryId) {
                    return
                }
                const saved = await writeRepository(
                    entry,
                    async () => {
                        await reviewHogRepositoriesPeopleDestroy(currentProjectId(), repositoryId, person.id)
                    },
                    'Could not remove the person. Try again.'
                )
                if (saved) {
                    posthog.capture('review hog repository person removed', { kind: person.kind })
                }
            },
            setMyChoice: async ({ entry, value }) => {
                const choiceId = entry.my_choice_id
                if (value === 'follow') {
                    // Following means no stored choice. Without one there is nothing to write.
                    if (!choiceId) {
                        return
                    }
                    const cleared = await writeRepository(
                        entry,
                        () => reviewHogRepositoryChoicesDestroy(currentProjectId(), choiceId),
                        'Could not clear your choice. Try again.'
                    )
                    if (cleared) {
                        posthog.capture('review hog repository choice cleared')
                    }
                    return
                }
                const saved = await writeRepository(
                    entry,
                    async () => {
                        await reviewHogRepositoryChoicesCreate(currentProjectId(), {
                            ...repositoryRef(entry),
                            mode: value,
                        })
                    },
                    'Could not save your choice. Try again.'
                )
                if (saved) {
                    posthog.capture('review hog repository choice set', { mode: value })
                }
            },
            setMyDefault: ({ mode }) => {
                actions.updateSettings({ default_review_mode: mode })
            },
            updateSettingsSuccess: ({ payload }) => {
                // The default decides the result in every repository without an own choice.
                if (payload && 'default_review_mode' in payload) {
                    posthog.capture('review hog default review mode changed', { mode: payload.default_review_mode })
                    actions.loadOverview()
                }
            },
        }
    }),

    afterMount(({ actions, values }) => {
        if (values.projectSettings !== null) {
            actions.loadOverview()
        }
    }),
])
