function templateProperties(template: HogFunctionTemplateWithSubTemplateType): Record<string, string> {
    return { template_id: template.id, template_name: template.name }
}

/**
 * The dialog that offers Workflows when a "Create" click in the destination catalog targets a tool that
 * competes with it. Step one is the choice, step two is a described workflow that the composer drafts.
 */
export const destinationCrossSellLogic = kea<destinationCrossSellLogicType>([
    path(['products', 'workflows', 'frontend', 'crossSell', 'destinationCrossSellLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], sceneAgentPanelLogic, ['sceneIntegrationEnabled']],
        actions: [teamLogic, ['addProductIntentForCrossSell']],
    })),
    actions({
        openModal: (template: HogFunctionTemplateWithSubTemplateType, destinationUrl: string) => ({
            template,
            destinationUrl,
        }),
        closeModal: true,
        resetModal: true,
        continueWithDestination: true,
        tryWorkflows: true,
        setStep: (step: DestinationCrossSellStep) => ({ step }),
        setPrompt: (prompt: string) => ({ prompt }),
        selectSuggestion: (suggestion: AiFirstSuggestion, index: number) => ({ suggestion, index }),
        submitPrompt: true,
        markDismissed: true,
    }),
    reducers({
        target: [
            null as DestinationCrossSellTarget | null,
            {
                openModal: (_, { template, destinationUrl }) => ({ template, destinationUrl }),
                resetModal: () => null,
            },
        ],
        step: [
            'intro' as DestinationCrossSellStep,
            {
                openModal: () => 'intro',
                setStep: (_, { step }) => step,
            },
        ],
        prompt: [
            '',
            {
                openModal: () => '',
                setPrompt: (_, { prompt }) => prompt,
                selectSuggestion: (_, { suggestion }) => suggestion.prompt,
            },
        ],
        usedSuggestion: [
            false,
            {
                openModal: () => false,
                setPrompt: () => false,
                selectSuggestion: () => true,
            },
        ],
        isDismissed: [
            false,
            // pinned: localStorage key. One "no" is the opt-out, so the flag has no expiry and no project prefix:
            // it follows the person into every project in this browser, the same as banner and nav ad dismissals.
            { persist: true },
            {
                markDismissed: () => true,
            },
        ],
    }),
    selectors({
        isOpen: [(s) => [s.target], (target: DestinationCrossSellTarget | null): boolean => !!target],
        crossSellEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.CDP_WORKFLOWS_CROSS_SELL],
        ],
        suggestions: [
            (s) => [s.target],
            (target: DestinationCrossSellTarget | null): AiFirstSuggestion[] =>
                target ? suggestionsForTemplate(target.template.id) : [],
        ],
        shouldIntercept: [
            (s) => [s.crossSellEnabled, s.isDismissed],
            (crossSellEnabled: boolean, isDismissed: boolean) =>
                (template: HogFunctionTemplateWithSubTemplateType): boolean =>
                    crossSellEnabled && !isDismissed && isWorkflowsCrossSellTemplate(template),
        ],
    }),
    listeners(({ actions, values }) => ({
        // pinned: analytics event names
        openModal: ({ template }) => {
            posthog.capture('workflows cross-sell modal shown', templateProperties(template))
        },
        closeModal: () => {
            const target = values.target
            if (!target) {
                return
            }
            posthog.capture('workflows cross-sell modal dismissed', {
                ...templateProperties(target.template),
                reason: 'closed',
                step: values.step,
            })
            actions.markDismissed()
            actions.resetModal()
        },
        continueWithDestination: () => {
            const target = values.target
            if (!target) {
                return
            }
            posthog.capture('workflows cross-sell modal dismissed', {
                ...templateProperties(target.template),
                reason: 'continue_with_destination',
                step: values.step,
            })
            actions.markDismissed()
            actions.resetModal()
            router.actions.push(target.destinationUrl)
        },
        tryWorkflows: () => {
            const target = values.target
            if (!target) {
                return
            }
            // Read at the click: the selector behind it records a flag exposure, which a catalog visit must not.
            const aiComposerAvailable = values.sceneIntegrationEnabled
            posthog.capture('workflows cross-sell accepted', {
                ...templateProperties(target.template),
                ai_composer_available: aiComposerAvailable,
            })
            actions.addProductIntentForCrossSell({
                from: ProductKey.PIPELINE_DESTINATIONS,
                to: ProductKey.WORKFLOWS,
                intent_context: ProductIntentContext.WORKFLOWS_CROSS_SELL_FROM_DESTINATION,
                metadata: { template_id: target.template.id },
            })
            // An accepted offer quiets the dialog too: the person knows about workflows now.
            actions.markDismissed()
            if (aiComposerAvailable) {
                actions.setStep('describe')
            } else {
                actions.resetModal()
                router.actions.push(urls.workflowNew())
            }
        },
        selectSuggestion: ({ index }) => {
            if (!values.target) {
                return
            }
            posthog.capture('workflows cross-sell suggestion selected', {
                ...templateProperties(values.target.template),
                suggestion_index: index,
            })
        },
        submitPrompt: () => {
            const target = values.target
            const prompt = values.prompt.trim()
            if (!target || !prompt) {
                return
            }
            posthog.capture('workflows cross-sell prompt submitted', {
                ...templateProperties(target.template),
                prompt_length: prompt.length,
                used_suggestion: values.usedSuggestion,
            })
            actions.resetModal()
            router.actions.push(urlForNewWorkflowComposerWithPrompt(prompt, WORKFLOWS_CROSS_SELL_SOURCE))
        },
    })),
])
