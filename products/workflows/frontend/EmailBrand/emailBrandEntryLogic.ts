export interface emailBrandEntryLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentTeamId: number | null // teamLogic
    enabled: boolean
    isOpen: boolean
    summary: EmailBrandApi | null
    summaryLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface emailBrandEntryLogicActions {
    closeFlow: () => {
        value: true
    }
    complete: (
        emailBrand: EmailBrandApi,
        templateId: string | null
    ) => {
        emailBrand: EmailBrandApi
        templateId: string | null
    }
    loadEmailBrandSummary: (_: any) => any
    loadEmailBrandSummaryFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadEmailBrandSummarySuccess: (
        summary: EmailBrandApi | null,
        payload?: any
    ) => {
        summary: EmailBrandApi | null
        payload?: any
    }
    openFlow: () => {
        value: true
    }
    setOpen: (isOpen: boolean) => {
        isOpen: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface emailBrandEntryLogicMeta {
    key: 'channels' | 'template_library'
    __keaTypeGenInternalSelectorTypes: {
        enabled: (featureFlags: FeatureFlagsSet) => boolean
    }
}

export type emailBrandEntryLogicType = MakeLogicType<
    emailBrandEntryLogicValues,
    emailBrandEntryLogicActions,
    EmailBrandEntryProps,
    emailBrandEntryLogicMeta
>

export const emailBrandEntryLogic = kea<emailBrandEntryLogicType>([
    props({} as EmailBrandEntryProps),
    key((props) => props.entryPoint),
    path((key) => ['products', 'workflows', 'emailBrandEntryLogic', key]),
    connect({ values: [featureFlagLogic, ['featureFlags'], teamLogic, ['currentTeamId']] }),
    actions({
        openFlow: true,
        closeFlow: true,
        setOpen: (isOpen: boolean) => ({ isOpen }),
        complete: (emailBrand: EmailBrandApi, templateId: string | null) => ({ emailBrand, templateId }),
    }),
    loaders(({ values, cache }) => ({
        summary: [
            null as EmailBrandApi | null,
            {
                loadEmailBrandSummary: async (_, breakpoint) => {
                    const revision = cache.summaryRevision ?? 0
                    try {
                        const result = await emailBrandCurrentRetrieve(String(values.currentTeamId))
                        return revision === (cache.summaryRevision ?? 0) ? result : values.summary
                    } catch (error) {
                        if (revision !== (cache.summaryRevision ?? 0)) {
                            return values.summary
                        }
                        if (error instanceof ApiError && error.status === 404) {
                            return null
                        }
                        throw error
                    } finally {
                        breakpoint()
                    }
                },
            },
        ],
    })),
    reducers({
        isOpen: [false, { setOpen: (_, { isOpen }) => isOpen, closeFlow: () => false, complete: () => false }],
        summary: { complete: (_, { emailBrand }) => emailBrand },
    }),
    selectors({
        enabled: [(s) => [s.featureFlags], (flags: FeatureFlagsSet): boolean => !!flags['workflows-brand-detection']],
    }),
    listeners(({ values, actions, props, cache }) => ({
        openFlow: () => {
            if (values.enabled) {
                actions.setOpen(true)
            }
        },
        complete: ({ templateId }) => {
            cache.summaryRevision = (cache.summaryRevision ?? 0) + 1
            if (props.entryPoint === 'template_library' && templateId) {
                router.actions.push(urls.workflowsLibraryTemplate(templateId))
            }
        },
    })),
    afterMount(({ props, actions, values }) => {
        if (values.enabled && props.entryPoint === 'channels') {
            actions.loadEmailBrandSummary({})
        }
    }),
])
