export const workflowSandboxSwitchBannerLogic = kea<workflowSandboxSwitchBannerLogicType>([
    props({} as WorkflowLogicProps),
    key((props) => props.id ?? 'new'),
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'workflowSandboxSwitchBannerLogic', key]),
    connect((props: WorkflowLogicProps) => ({
        values: [
            workflowLogic(props),
            ['workflow', 'workflowUserAccessLevel'],
            integrationsLogic,
            ['ownEmailIntegrations', 'sandboxEmailSender'],
        ],
        actions: [
            workflowLogic(props),
            ['setWorkflowValues', 'autoSaveWorkflow'],
            integrationsLogic,
            ['loadIntegrationsSuccess'],
        ],
    })),
    actions({
        switchToOwnSender: (integrationId: number) => ({ integrationId }),
        reportBannerShown: true,
    }),
    reducers({
        bannerShownReported: [false, { reportBannerShown: () => true }],
    }),
    selectors({
        verifiedOwnSenders: [
            (s) => [s.ownEmailIntegrations],
            (ownEmailIntegrations: IntegrationType[]): IntegrationType[] =>
                ownEmailIntegrations.filter((integration) => integration.config?.verified === true),
        ],
        sandboxEmailSteps: [
            (s) => [s.workflow, s.sandboxEmailSender],
            (workflow: HogFlow, sandboxEmailSender: IntegrationType | null): EmailStep[] =>
                sandboxEmailSender
                    ? workflow.actions.filter(isEmailStep).filter((step) => usesSender(step, sandboxEmailSender.id))
                    : [],
        ],
        bannerVisible: [
            (s) => [s.sandboxEmailSteps, s.verifiedOwnSenders],
            (sandboxEmailSteps: EmailStep[], verifiedOwnSenders: IntegrationType[]): boolean =>
                sandboxEmailSteps.length > 0 && verifiedOwnSenders.length > 0,
        ],
    }),
    listeners(({ actions, values, props }) => {
        const reportBannerShownOnce = (): void => {
            if (values.bannerVisible && !values.bannerShownReported) {
                actions.reportBannerShown()
            }
        }
        return {
            [workflowLogic(props).actionTypes.loadWorkflowSuccess]: reportBannerShownOnce,
            loadIntegrationsSuccess: reportBannerShownOnce,
            setWorkflowValues: reportBannerShownOnce,
            reportBannerShown: () => {
                posthog.capture('workflows sandbox switch banner shown')
            },
            switchToOwnSender: ({ integrationId }) => {
                const { sandboxEmailSteps } = values
                if (sandboxEmailSteps.length === 0) {
                    return
                }
                const switched = new Map(sandboxEmailSteps.map((step) => [step.id, withSender(step, integrationId)]))
                actions.setWorkflowValues({
                    actions: values.workflow.actions.map((action) => switched.get(action.id) ?? action),
                })
                actions.autoSaveWorkflow()
                posthog.capture('workflows sandbox sender switched', { email_step_count: sandboxEmailSteps.length })
                const sender = values.verifiedOwnSenders.find((candidate) => candidate.id === integrationId)
                lemonToast.success(
                    `Switched ${pluralize(sandboxEmailSteps.length, 'email step')} to ${sender?.config.email ?? 'your own sender'}`
                )
            },
        }
    }),
])
