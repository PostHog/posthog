export type EmailStep = Extract<HogFlowAction, { type: 'function_email' }>

const isEmailStep = (action: HogFlowAction): action is EmailStep => action.type === 'function_email'

const usesSender = (step: EmailStep, senderId: number): boolean =>
    selectedSenderIds(step.config.inputs?.email?.value?.from).includes(senderId)

const withSender = (step: EmailStep, integrationId: number): EmailStep => {
    const email = step.config.inputs.email
    return {
        ...step,
        config: {
            ...step.config,
            inputs: {
                ...step.config.inputs,
                email: { ...email, value: { ...email.value, from: { integrationId } } },
            },
        },
    }
}

