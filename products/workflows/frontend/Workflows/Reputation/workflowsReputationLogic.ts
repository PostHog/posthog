export const workflowsReputationLogic = kea<workflowsReputationLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'Reputation', 'workflowsReputationLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
        actions: [supportLogic, ['openSupportForm']],
    })),
    actions({
        // Declared here (as well as auto-created by the loader) so kea-typegen sees a payload-less
        // action; without this, TS types the first loader arg as required and callers fail typecheck.
        loadReputation: true,
        reportSuspensionBannerShown: true,
        requestSendingReview: true,
        setSearch: (search: string) => ({ search }),
    }),
    reducers({
        search: [
            '',
            {
                setSearch: (_, { search }) => search,
            },
        ],
        // Search reloads the response on every keystroke, so without this the "shown" event would
        // count typing rather than the banner appearing. Reset once sending resumes, so a project
        // suspended again later still reports that second episode.
        suspensionBannerReported: [
            false,
            {
                reportSuspensionBannerShown: () => true,
                loadReputationSuccess: (reported, { reputationResponse }) =>
                    suspensionCauseFromResponse(reputationResponse) ? reported : false,
            },
        ],
    }),
    loaders(({ values }) => ({
        reputationResponse: [
            null as TeamEmailReputationResponseApi | null,
            {
                loadReputation: async (_, breakpoint) => {
                    if (!values.currentProjectId) {
                        return null
                    }
                    const search = values.search.trim()
                    const response = await hogFlowsReputationRetrieve(
                        String(values.currentProjectId),
                        search ? { search } : undefined
                    )
                    breakpoint() // a newer load superseded this one; discard the stale response
                    return response
                },
            },
        ],
    })),
    listeners(({ actions, values }) => {
        const suspensionProperties = (): Record<string, any> => ({
            cause: values.suspensionCause,
            open_findings: values.awsReputation?.findings.length ?? 0,
            bounce_rate: values.teamReputation?.bounce_rate ?? null,
            complaint_rate: values.teamReputation?.complaint_rate ?? null,
        })
        return {
            // Search filters server-side (the response is capped to the worst 50 workflows), so each
            // keystroke needs a reload — debounced via the loader's own breakpoint on rapid typing.
            setSearch: async (_, breakpoint) => {
                await breakpoint(250)
                actions.loadReputation()
            },
            loadReputationSuccess: () => {
                if (values.suspensionCause && !values.suspensionBannerReported) {
                    actions.reportSuspensionBannerShown()
                }
            },
            reportSuspensionBannerShown: () => {
                // pinned: analytics event name — renaming breaks dashboards
                posthog.capture('workflow email suspension banner shown', suspensionProperties())
            },
            requestSendingReview: () => {
                // pinned: analytics event name — renaming breaks dashboards
                posthog.capture('workflow email sending review requested', suspensionProperties())
                actions.openSupportForm({
                    kind: 'support',
                    isEmailFormOpen: true,
                    message: buildSendingReviewMessage({
                        cause: values.suspensionCause ?? 'provider',
                        reason: values.suspensionReason,
                        reputation: values.teamReputation,
                        findings: values.awsReputation?.findings ?? [],
                    }),
                })
            },
        }
    }),
    selectors({
        awsReputation: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): AwsTenantReputationApi | null => response?.aws ?? null,
        ],
        sendingAllowance: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): EmailSendingAllowanceApi | null =>
                response?.sending_allowance ?? null,
        ],
        teamReputation: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): EmailSendingRatesApi | null =>
                response?.reputation ?? null,
        ],
        ispSendingHealth: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly IspSendingHealthApi[] => response?.isps ?? [],
        ],
        ispSharedDomains: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly string[] => response?.isp_shared_domains ?? [],
        ],
        ispWithheldDomains: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly string[] =>
                response?.isp_withheld_domains ?? [],
        ],
        suspensionCause: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): SuspensionCause | null =>
                suspensionCauseFromResponse(response),
        ],
        suspensionReason: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): string =>
                response?.email_sending_suspension_reason ?? '',
        ],
        workflowSnapshots: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly WorkflowEmailSendingRatesApi[] =>
                response?.workflows ?? [],
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadReputation()
    }),
])
