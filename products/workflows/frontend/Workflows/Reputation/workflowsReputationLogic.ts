export const workflowsReputationLogic = kea<workflowsReputationLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'Reputation', 'workflowsReputationLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], router, ['location']],
    })),
    actions({
        // Declared here (as well as auto-created by the loaders) so kea-typegen sees payload-less
        // actions; without this, TS types the first loader arg as required and callers fail typecheck.
        loadReputation: true,
        searchWorkflows: true,
        setSearch: (search: string) => ({ search }),
        toggleShowAllActions: true,
        setActiveBreakdownTab: (tab: ReputationBreakdownTab) => ({ tab }),
    }),
    loaders(({ values }) => ({
        // Always unsearched: everything above the workflow table reads from this, and a search
        // only narrows the table.
        reputationResponse: [
            null as TeamEmailReputationResponseApi | null,
            {
                loadReputation: async (_, breakpoint) => {
                    if (!values.currentProjectId) {
                        return null
                    }
                    const response = await hogFlowsReputationRetrieve(String(values.currentProjectId))
                    breakpoint() // a newer load superseded this one; discard the stale response
                    return response
                },
            },
        ],
        workflowSearchResults: [
            null as WorkflowSearchResults | null,
            {
                searchWorkflows: async (_, breakpoint) => {
                    const search = values.search.trim()
                    if (!search || !values.currentProjectId) {
                        return null
                    }
                    try {
                        const response = await hogFlowsReputationRetrieve(String(values.currentProjectId), {
                            search,
                        })
                        breakpoint() // a newer search superseded this one; discard the stale response
                        return { search, workflows: response.workflows, failed: false }
                    } catch {
                        breakpoint()
                        // The table says the search failed, which a toast alone does not do for a
                        // network error, and the rows of the previous term must not stay on screen.
                        return { search, workflows: [], failed: true }
                    }
                },
            },
        ],
    })),
    reducers({
        search: [
            '',
            {
                setSearch: (_, { search }) => search,
            },
        ],
        reputationLoadError: [
            null as ReputationLoadError | null,
            {
                loadReputation: () => null,
                loadReputationSuccess: () => null,
                loadReputationFailure: (_, { errorObject }) => (errorObject?.status === 403 ? 'forbidden' : 'failed'),
            },
        ],
        showAllActions: [
            false,
            {
                toggleShowAllActions: (state) => !state,
            },
        ],
        activeBreakdownTab: [
            'workflows' as ReputationBreakdownTab,
            {
                setActiveBreakdownTab: (_, { tab }) => tab,
            },
        ],
    }),
    listeners(({ actions }) => ({
        // Search filters server-side (the response is capped to the worst 50 workflows), so each
        // keystroke needs a reload, debounced here and made stale-safe by the loader's breakpoint.
        setSearch: async (_, breakpoint) => {
            await breakpoint(250)
            actions.searchWorkflows()
        },
    })),
    selectors({
        awsReputation: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): AwsTenantReputationApi | null => response?.aws ?? null,
        ],
        sendingAllowance: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): EmailSendingAllowanceApi | null =>
                response?.sending_allowance ?? null,
        ],
        teamReputation: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): EmailSendingRatesApi | null =>
                response?.reputation ?? null,
        ],
        ispSendingHealth: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly IspSendingHealthApi[] => response?.isps ?? [],
        ],
        ispSharedDomains: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly string[] => response?.isp_shared_domains ?? [],
        ],
        ispWithheldDomains: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly string[] =>
                response?.isp_withheld_domains ?? [],
        ],
        workflowSnapshots: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly WorkflowEmailSendingRatesApi[] =>
                response?.workflows ?? [],
        ],
        // A provisioned tenant reports healthy before the project sends anything, so a verdict
        // alone only counts when it says something is wrong.
        hasSendingData: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): boolean =>
                !!response &&
                (!!response.reputation ||
                    response.workflows.length > 0 ||
                    response.isps.length > 0 ||
                    response.isp_withheld_domains.length > 0 ||
                    response.email_sending_suspended ||
                    (!!response.aws &&
                        (response.aws.findings.length > 0 ||
                            response.aws.health !== 'healthy' ||
                            response.aws.sending_status === 'DISABLED'))),
        ],
        // The tab renders under both /workflows and /broadcasts, and switching tabs must not leave
        // the surface the person is on.
        tabUrl: [
            (s) => [s.location],
            (location: { pathname: string }): ((tab: ReputationSetupTab) => string) =>
                location.pathname.includes(urls.broadcasts()) ? urls.broadcasts : urls.workflows,
        ],
        reputationActions: [
            (s) => [s.reputationResponse, s.tabUrl],
            (
                response: TeamEmailReputationResponseApi | null,
                tabUrl: (tab: ReputationSetupTab) => string
            ): ReputationAction[] =>
                response
                    ? buildReputationActions({
                          aws: response.aws,
                          rates: response.reputation,
                          workflows: response.workflows,
                          isps: response.isps,
                          sharedDomains: response.isp_shared_domains,
                          suspended: response.email_sending_suspended,
                          tabUrl,
                      })
                    : [],
        ],
        tableWorkflows: [
            (s) => [s.search, s.workflowSnapshots, s.workflowSearchResults],
            (
                search: string,
                workflowSnapshots: readonly WorkflowEmailSendingRatesApi[],
                results: WorkflowSearchResults | null
            ): readonly WorkflowEmailSendingRatesApi[] => {
                const term = search.trim()
                if (!term) {
                    return workflowSnapshots
                }
                return results?.search === term ? results.workflows : []
            },
        ],
        workflowSearchFailed: [
            (s) => [s.search, s.workflowSearchResults],
            (search: string, results: WorkflowSearchResults | null): boolean =>
                !!results?.failed && results.search === search.trim(),
        ],
        // The search starts after a debounce, so the typed term runs ahead of the loader. The
        // table counts as loading until the rows answer the term on screen.
        tableLoading: [
            (s) => [s.reputationResponseLoading, s.search, s.workflowSearchResults],
            (reputationResponseLoading: boolean, search: string, results: WorkflowSearchResults | null): boolean => {
                const term = search.trim()
                return reputationResponseLoading || (!!term && results?.search !== term)
            },
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadReputation()
    }),
])
