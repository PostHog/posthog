// The first line of every tier increase ticket. Support searches tickets on this exact text, so keep it stable.
const SENDING_TIER_INCREASE_TICKET_MARKER = 'Email sending tier increase request'

const SENDING_TIER_INCREASE_PROMPT = [
    'How many emails do you need to send per day?',
    '',
    '',
    "What supports the increase? For example, if you're moving from another email provider, tell us which one, roughly how many emails you sent there each month, and your bounce and spam complaint rates there.",
    '',
    "If you're able to, please upload screenshots of any supporting evidence.",
].join('\n')

function sendingTierIncreaseContext(
    projectId: number | null,
    allowance: EmailSendingAllowanceApi,
    rates: EmailSendingRatesApi | null
): string {
    return [
        SENDING_TIER_INCREASE_TICKET_MARKER,
        `Project ID: ${projectId ?? 'unknown'}`,
        `Current tier: ${allowance.tier} of ${allowance.max_tier}`,
        `Emails today: ${humanFriendlyNumber(allowance.emails_sent_last_day)} of ${humanFriendlyNumber(allowance.emails_per_day)}`,
        `Emails this hour: ${humanFriendlyNumber(allowance.emails_sent_last_hour)} of ${humanFriendlyNumber(allowance.emails_per_hour)}`,
        ...(rates
            ? [
                  `Bounce rate (last 30 days): ${percentage(rates.bounce_rate, 2, true)}`,
                  `Spam complaint rate (last 30 days): ${percentage(rates.complaint_rate, 2, true)}`,
              ]
            : []),
    ].join('\n')
}

