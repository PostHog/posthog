export type reputationResponseLogicType = MakeLogicType<
    reputationResponseLogicValues,
    reputationResponseLogicActions,
    Record<string, any>,
    reputationResponseLogicMeta
>

export const reputationResponseLogic = kea<reputationResponseLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'Reputation', 'reputationResponseLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        // Declared here (as well as auto-created by the loader) so kea-typegen sees a payload-less
        // action; without this, TS types the first loader arg as required and callers fail typecheck.
        loadReputation: true,
    }),
    loaders(({ values }) => ({
        // Always unsearched: a table search only narrows the table, never what is above it.
        reputationResponse: [
            null as TeamEmailReputationResponseApi | null,
            {
                loadReputation: async (_, breakpoint) => {
                    if (!values.currentProjectId) {
                        return null
                    }
                    const response = await hogFlowsReputationRetrieve(String(values.currentProjectId))
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    reducers({
        reputationLoadError: [
            null as ReputationLoadError | null,
            {
                loadReputation: () => null,
                loadReputationSuccess: () => null,
                loadReputationFailure: (_, { errorObject }) => (errorObject?.status === 403 ? 'forbidden' : 'failed'),
            },
        ],
    }),
    selectors({
        awsReputation: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): AwsTenantReputationApi | null => response?.aws ?? null,
        ],
        sendingAllowance: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): EmailSendingAllowanceApi | null =>
                response?.sending_allowance ?? null,
        ],
        teamReputation: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): EmailSendingRatesApi | null =>
                response?.reputation ?? null,
        ],
        ispSendingHealth: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly IspSendingHealthApi[] => response?.isps ?? [],
        ],
        ispSharedDomains: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly string[] => response?.isp_shared_domains ?? [],
        ],
        ispWithheldDomains: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly string[] =>
                response?.isp_withheld_domains ?? [],
        ],
        emailSendingSuspended: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): boolean => !!response?.email_sending_suspended,
        ],
        workflowSnapshots: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): readonly WorkflowEmailSendingRatesApi[] =>
                response?.workflows ?? [],
        ],
        // A provisioned tenant reports healthy before the project sends anything, so a verdict
        // alone only counts when it says something is wrong.
        hasSendingData: [
            (s) => [s.reputationResponse],
            (response: TeamEmailReputationResponseApi | null): boolean =>
                !!response &&
                (!!response.reputation ||
                    response.workflows.length > 0 ||
                    response.isps.length > 0 ||
                    response.isp_withheld_domains.length > 0 ||
                    response.email_sending_suspended ||
                    isSendingStopped(response.aws) ||
                    (!!response.aws && (response.aws.findings.length > 0 || response.aws.health !== 'healthy'))),
        ],
        // The all-clear may only say providers are under the bounce line when at least one of them
        // has enough email to judge.
        hasJudgedProviders: [
            (s) => [s.ispSendingHealth],
            (isps: readonly IspSendingHealthApi[]): boolean =>
                isps.some((isp) => isp.bounce_rate !== null && isp.emails_sent >= minimumVolumeToClassify('bounce')),
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadReputation()
    }),
])
