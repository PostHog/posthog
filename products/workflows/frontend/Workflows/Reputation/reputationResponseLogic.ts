import { MakeLogicType, actions, afterMount, connect, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { projectLogic } from 'scenes/projectLogic'

import { hogFlowsReputationRetrieve } from 'products/workflows/frontend/generated/api'
import type {
    AwsTenantReputationApi,
    EmailSendingAllowanceApi,
    EmailSendingRatesApi,
    IspSendingHealthApi,
    TeamEmailReputationResponseApi,
    WorkflowEmailSendingRatesApi,
} from 'products/workflows/frontend/generated/api.schemas'

import { isSendingStopped, minimumVolumeToClassify } from './reputationUtils'

export type ReputationLoadError = 'forbidden' | 'failed'

