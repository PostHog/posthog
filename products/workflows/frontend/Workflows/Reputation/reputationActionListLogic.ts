import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'

import { supportLogic } from 'lib/components/Support/supportLogic'
import { urls } from 'scenes/urls'

import type { TeamEmailReputationResponseApi } from 'products/workflows/frontend/generated/api.schemas'

import { buildReputationActions } from './actions/reputationActionRegistry'
import type {
    ReputationAction,
    ReputationBreakdownTab,
    ReputationPageControls,
    ReputationSetupTab,
} from './actions/reputationActionTypes'
import { reputationResponseLogic } from './reputationResponseLogic'

