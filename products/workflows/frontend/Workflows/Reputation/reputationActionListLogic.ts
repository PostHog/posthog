import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'

import { supportLogic } from 'lib/components/Support/supportLogic'
import { urls } from 'scenes/urls'

import type { TeamEmailReputationResponseApi } from 'products/workflows/frontend/generated/api.schemas'

import { ReputationActionContext, buildReputationActionContext } from './actions/reputationActionContext'
import { buildReputationActions } from './actions/reputationActionRegistry'
import type {
    ReputationAction,
    ReputationBreakdownTab,
    ReputationPageControls,
    ReputationSetupTab,
} from './actions/reputationActionTypes'
import { reputationResponseLogic } from './reputationResponseLogic'

export const BREAKDOWN_ELEMENT_ID = 'workflows-reputation-breakdown'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reputationActionListLogicValues {
    reputationResponse: TeamEmailReputationResponseApi | null // reputationResponseLogic
    location: {
        pathname: string
        search: string
        hash: string
    } // router
    activeBreakdownTab: ReputationBreakdownTab
    providersOverLineCount: number
    reputationActionContext: ReputationActionContext | null
    reputationActions: ReputationAction[]
    showAllActions: boolean
    tabUrl: (tab: ReputationSetupTab) => string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reputationActionListLogicActions {
    openSupportForm: (
        values: Partial<import('lib/components/Support/supportLogic').SupportFormFields> & {
            target?: 'modal' | 'sidePanel'
        }
    ) => Partial<import('lib/components/Support/supportLogic').SupportFormFields> & {
        target?: 'modal' | 'sidePanel' | undefined
    } // supportLogic
    runActionCta: (key: string) => {
        key: string
    }
    setActiveBreakdownTab: (tab: ReputationBreakdownTab) => {
        tab: ReputationBreakdownTab
    }
    showBreakdown: (tab: ReputationBreakdownTab) => {
        tab: ReputationBreakdownTab
    }
    toggleShowAllActions: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reputationActionListLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        tabUrl: (location: { hash: string; pathname: string; search: string }) => (tab: ReputationSetupTab) => string
        reputationActionContext: (
            reputationResponse: TeamEmailReputationResponseApi | null,
            tabUrl: (tab: ReputationSetupTab) => string
        ) => ReputationActionContext | null
        reputationActions: (reputationActionContext: ReputationActionContext | null) => ReputationAction[]
        providersOverLineCount: (reputationActionContext: ReputationActionContext | null) => number
    }
}

export type reputationActionListLogicType = MakeLogicType<
    reputationActionListLogicValues,
    reputationActionListLogicActions,
    Record<string, any>,
    reputationActionListLogicMeta
>

export const reputationActionListLogic = kea<reputationActionListLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'Reputation', 'reputationActionListLogic']),
    connect(() => ({
        values: [reputationResponseLogic, ['reputationResponse'], router, ['location']],
        actions: [supportLogic, ['openSupportForm']],
    })),
    actions({
        toggleShowAllActions: true,
        setActiveBreakdownTab: (tab: ReputationBreakdownTab) => ({ tab }),
        showBreakdown: (tab: ReputationBreakdownTab) => ({ tab }),
        runActionCta: (key: string) => ({ key }),
    }),
    reducers({
        showAllActions: [
            false,
            {
                toggleShowAllActions: (state) => !state,
            },
        ],
        activeBreakdownTab: [
            'workflows' as ReputationBreakdownTab,
            {
                setActiveBreakdownTab: (_, { tab }) => tab,
                showBreakdown: (_, { tab }) => tab,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        // The breakdown sits below the action list, so the button that opens a tab also brings it
        // into view, and moves keyboard focus there so it does not stay on an off-screen button.
        // The wait lets React render the tab first.
        showBreakdown: async (_, breakpoint) => {
            await breakpoint(0)
            const breakdown = document.getElementById(BREAKDOWN_ELEMENT_ID)
            breakdown?.scrollIntoView({ block: 'start' })
            breakdown?.querySelector<HTMLElement>('[role="tab"][aria-selected="true"]')?.focus({ preventScroll: true })
        },
        runActionCta: ({ key }) => {
            const onClick = values.reputationActions.find((action) => action.key === key)?.cta?.onClick
            if (!onClick) {
                return
            }
            const page: ReputationPageControls = {
                openSupportForm: (message) => actions.openSupportForm({ kind: 'support', message }),
                showBreakdown: actions.showBreakdown,
            }
            onClick(page)
        },
    })),
    selectors({
        // The tab renders under both /workflows and /broadcasts, and switching tabs must not leave
        // the surface the person is on.
        tabUrl: [
            (s) => [s.location],
            (location: { pathname: string }): ((tab: ReputationSetupTab) => string) =>
                location.pathname.includes(urls.broadcasts()) ? urls.broadcasts : urls.workflows,
        ],
        reputationActionContext: [
            (s) => [s.reputationResponse, s.tabUrl],
            (
                response: TeamEmailReputationResponseApi | null,
                tabUrl: (tab: ReputationSetupTab) => string
            ): ReputationActionContext | null => (response ? buildReputationActionContext({ response, tabUrl }) : null),
        ],
        reputationActions: [
            (s) => [s.reputationActionContext],
            (context: ReputationActionContext | null): ReputationAction[] =>
                context ? buildReputationActions(context) : [],
        ],
        providersOverLineCount: [
            (s) => [s.reputationActionContext],
            (context: ReputationActionContext | null): number => context?.providersOverLine.length ?? 0,
        ],
    }),
])
