import { MakeLogicType, actions, connect, kea, listeners, path } from 'kea'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { readHandoffSource } from 'scenes/max/aiFirstCreate/aiFirstMode'
import { MAX_SIDE_PANEL_ID } from 'scenes/max/components/PhaiSidePanelChat'
import { aiConsentLogic } from 'scenes/settings/organization/aiConsentLogic'

import { composerSeedLogic } from 'products/posthog_ai/frontend/api/logics'
import type { ComposerSeed } from 'products/posthog_ai/frontend/api/logics'

import { COMPOSER_PROMPT_PARAM, readComposerPrompt } from './newWorkflowComposerPrompt'
import { newWorkflowLogic } from './newWorkflowLogic'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newWorkflowComposerPromptLogicValues {
    dataProcessingAccepted: boolean // aiConsentLogic
    aiComposerAvailable: boolean // newWorkflowLogic
    location: {
        pathname: string
        search: string
        hash: string
    } // router
    searchParams: Record<string, any> // router
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newWorkflowComposerPromptLogicActions {
    setSeed: (seed: ComposerSeed) => {
        seed: ComposerSeed
    } // composerSeedLogic
    consumeComposerPrompt: () => {
        value: true
    }
}

export type newWorkflowComposerPromptLogicType = MakeLogicType<
    newWorkflowComposerPromptLogicValues,
    newWorkflowComposerPromptLogicActions
>

/**
 * Hands a `?prompt=` from the new-workflow URL to the composer. The scene dispatches `consumeComposerPrompt`
 * once the composer is on screen, because a seed applied before the composer's mount effects is emptied by
 * them and would go out without the draft-first context.
 */
export const newWorkflowComposerPromptLogic = kea<newWorkflowComposerPromptLogicType>([
    path(['products', 'workflows', 'frontend', 'newWorkflowComposerPromptLogic']),
    connect(() => ({
        values: [
            newWorkflowLogic,
            ['aiComposerAvailable'],
            aiConsentLogic,
            ['dataProcessingAccepted'],
            router,
            ['searchParams', 'location'],
        ],
        actions: [composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }), ['setSeed']],
    })),
    actions({
        consumeComposerPrompt: true,
    }),
    listeners(({ actions, values }) => ({
        consumeComposerPrompt: () => {
            const prompt = readComposerPrompt(values.searchParams)
            if (!prompt) {
                return
            }
            const source = readHandoffSource(values.searchParams)
            const { [COMPOSER_PROMPT_PARAM]: _consumed, ...remainingSearch } = values.searchParams
            // The prompt leaves the URL before the seed is set, so a reload cannot submit it a second time.
            // `source` stays: it keeps the composer open for this handoff and names it in analytics.
            router.actions.replace(values.location.pathname, remainingSearch, router.values.hashParams)
            if (!values.aiComposerAvailable) {
                return
            }
            // The prompt is URL-controlled, so it auto-submits only under the same organization-level AI data
            // processing consent as every other seeded prompt. Without consent it only prefills the composer.
            const autoSubmit = values.dataProcessingAccepted
            // pinned: analytics event name
            posthog.capture('workflow ai composer prompt prefilled', {
                source,
                prompt_length: prompt.length,
                auto_submitted: autoSubmit,
            })
            actions.setSeed({ prompt, autoSubmit })
        },
    })),
])
