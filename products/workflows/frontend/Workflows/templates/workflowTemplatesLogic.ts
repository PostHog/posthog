import { MakeLogicType, actions, afterMount, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { actionToUrl, router, urlToAction } from 'kea-router'

import api from 'lib/api'
import { createFuse, Fuse } from 'lib/utils/fuseSearch'
import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { urls } from 'scenes/urls'

import type { HogFlowTemplate } from '../hogflows/types'

// The template chooser also opens on host scenes, such as a cohort page. Only the workflows list
// reads these filters back from the URL, so a URL write from any other route would navigate the
// person away from the scene where they opened the chooser.
function onWorkflowsList(): boolean {
    return removeProjectIdIfPresent(router.values.location.pathname) === urls.workflows()
}

