export type customerioImportLogicType = MakeLogicType<
    customerioImportLogicValues,
    customerioImportLogicActions,
    Record<string, any>,
    customerioImportLogicMeta
>

export const customerioImportLogic = kea<customerioImportLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'import', 'customerioImportLogic']),
    actions({
        openImportModal: true,
        closeImportModal: true,
        setFiles: (files: File[]) => ({ files }),
        setParsed: (parsed: ParsedCustomerioFile | null, parseError: string | null) => ({ parsed, parseError }),
    }),
    reducers({
        files: [
            [] as File[],
            {
                setFiles: (_, { files }) => files,
                closeImportModal: () => [],
            },
        ],
        isImportModalOpen: [
            false,
            {
                openImportModal: () => true,
                closeImportModal: () => false,
            },
        ],
        parsed: [
            null as ParsedCustomerioFile | null,
            {
                setParsed: (_, { parsed }) => parsed,
                closeImportModal: () => null,
            },
        ],
        parseError: [
            null as string | null,
            {
                setParsed: (_, { parseError }) => parseError,
                closeImportModal: () => null,
            },
        ],
    }),
    loaders(({ values }) => ({
        results: [
            null as (WorkflowImportResponseApi & { dryRun: boolean }) | null,
            {
                runImport: async ({ dryRun }: { dryRun: boolean }) => {
                    const parsed = values.parsed
                    if (!parsed?.campaigns.length) {
                        return null
                    }
                    const response = await workflowImportsCreate(String(ApiConfig.getCurrentTeamId()), {
                        source: 'customerio',
                        ...parsed,
                        dry_run: dryRun,
                    })
                    if (dryRun && values.parsed !== parsed) {
                        // The files changed while the preview ran, so it describes files that are gone.
                        return null
                    }
                    return { ...response, dryRun }
                },
                resetResults: () => null,
            },
        ],
    })),
    selectors({
        campaignCount: [
            (s) => [s.parsed],
            (parsed: ParsedCustomerioFile | null): number => parsed?.campaigns.length ?? 0,
        ],
    }),
    listeners(({ actions, values }) => ({
        setFiles: async ({ files }) => {
            if (!values.resultsLoading) {
                actions.resetResults()
            }
            // Cleared while the files are read, so Preview can't send the previous selection.
            actions.setParsed(null, null)
            if (!files.length) {
                return
            }
            try {
                const parsed = parseCustomerioFiles(await Promise.all(files.map((file) => file.text())))
                if (values.files !== files) {
                    return
                }
                actions.setParsed(
                    parsed,
                    parsed.campaigns.length
                        ? null
                        : 'No automations found. Save each automation with the Customer.io CLI, as shown above.'
                )
            } catch (error) {
                if (values.files !== files) {
                    return
                }
                actions.setParsed(null, error instanceof Error ? error.message : 'The files could not be read.')
            }
        },
        openImportModal: () => {
            // pinned: analytics event name — renaming breaks dashboards. The import itself is tracked server-side.
            posthog.capture('workflows customerio import opened')
        },
        runImportSuccess: ({ results }) => {
            if (results && !results.dryRun) {
                workflowsLogic.findMounted()?.actions.loadWorkflows()
            }
        },
        runImportFailure: ({ error }) => {
            lemonToast.error(`The import failed: ${error}`)
        },
        closeImportModal: () => {
            actions.resetResults()
        },
    })),
])
