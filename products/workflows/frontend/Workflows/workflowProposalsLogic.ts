export const workflowProposalsLogic = kea<workflowProposalsLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'workflowProposalsLogic']),
    props({} as WorkflowProposalsLogicProps),
    key(({ id }) => id),
    connect(({ id }: WorkflowProposalsLogicProps) => ({
        values: [teamLogic, ['currentTeamIdStrict'], workflowLogic({ id }), ['hasStagedDraft', 'originalWorkflow']],
    })),
    actions({
        approveProposal: (proposalId: string) => ({ proposalId }),
        confirmApproveProposal: (proposalId: string, expectedDraftUpdatedAt: string | null) => ({
            proposalId,
            expectedDraftUpdatedAt,
        }),
        rejectProposal: (proposalId: string) => ({ proposalId }),
        confirmRejectProposal: (proposalId: string) => ({ proposalId }),
        setResolvingId: (proposalId: string | null, action: 'approve' | 'reject' | null = null) => ({
            proposalId,
            action,
        }),
        loadOutcome: (proposalId: string) => ({ proposalId }),
        setOutcome: (proposalId: string, outcome: WorkflowProposalOutcomeApi) => ({ proposalId, outcome }),
    }),
    reducers({
        resolvingId: [
            null as string | null,
            {
                setResolvingId: (_, { proposalId }) => proposalId,
            },
        ],
        // Which action is in flight, so each button shows its own spinner rather than both reading
        // the same id.
        resolvingAction: [
            null as 'approve' | 'reject' | null,
            {
                setResolvingId: (_, { action }) => action,
            },
        ],
        // Merge each finished request's entry here at reducer time, not inside the request. A request
        // that read prior state to build the merged map would read it stale, so two near-simultaneous
        // loads would drop each other's entry.
        outcomes: [
            {} as Record<string, WorkflowProposalOutcomeApi>,
            {
                setOutcome: (state, { proposalId, outcome }) => ({ ...state, [proposalId]: outcome }),
            },
        ],
    }),
    loaders(({ props, values }) => ({
        appliedResponse: [
            null as PaginatedWorkflowProposalListApi | null,
            {
                loadApplied: async () => {
                    try {
                        return await hogFlowsProposalsList(String(values.currentTeamIdStrict), props.id, {
                            status: 'applied',
                            limit: APPLIED_OUTCOME_LIMIT,
                        })
                    } catch (error) {
                        // Only the flag-off 404 is an empty queue. Let a 5xx or a dropped connection reject
                        // so the loader keeps the last known list and surfaces the failure, rather than
                        // blanking the panel and staying silent.
                        if (error instanceof ApiError && error.status === 404) {
                            return { count: 0, results: [] }
                        }
                        throw error
                    }
                },
            },
        ],
        proposalsResponse: [
            null as PaginatedWorkflowProposalListApi | null,
            {
                loadProposals: async () => {
                    try {
                        return await hogFlowsProposalsList(String(values.currentTeamIdStrict), props.id, {
                            status: 'suggested',
                        })
                    } catch (error) {
                        // A panel nobody asked for must not shout. The endpoint 404s wherever the flag is
                        // off, and the loader's default failure toast would put "Load proposals failed" in
                        // front of every user the backend rollout hasn't reached. But a 5xx or a dropped
                        // connection is a real failure: let it reject so the loader keeps the last known
                        // list and surfaces it, rather than erasing pending suggestions on a failed reload.
                        if (error instanceof ApiError && error.status === 404) {
                            return { count: 0, results: [] }
                        }
                        throw error
                    }
                },
            },
        ],
    })),
    selectors({
        appliedProposals: [
            (s) => [s.appliedResponse],
            (response: PaginatedWorkflowProposalListApi | null): WorkflowProposalApi[] => response?.results ?? [],
        ],
        pendingProposals: [
            (s) => [s.proposalsResponse],
            (response: PaginatedWorkflowProposalListApi | null): WorkflowProposalApi[] => response?.results ?? [],
        ],
    }),
    listeners(({ actions, props, values }) => ({
        approveProposal: ({ proposalId }) => {
            if (values.resolvingId !== null) {
                return
            }
            // The stamp of the draft this confirmation is about. Approve sends it as a fence, so a
            // draft staged or edited after this dialog opened returns 409 instead of being clobbered.
            const expectedDraftUpdatedAt = values.originalWorkflow?.draft_updated_at ?? null
            LemonDialog.open({
                title: 'Approve this suggestion?',
                description: values.hasStagedDraft
                    ? 'This replaces your current staged draft with the suggested change. The live workflow keeps running until you publish.'
                    : 'This opens the suggested change on the canvas as a draft. The live workflow keeps running until you publish.',
                primaryButton: {
                    children: 'Approve as draft',
                    onClick: () => actions.confirmApproveProposal(proposalId, expectedDraftUpdatedAt),
                },
                secondaryButton: {
                    children: 'Cancel',
                },
            })
        },
        confirmApproveProposal: async ({ proposalId, expectedDraftUpdatedAt }) => {
            if (values.resolvingId !== null) {
                return
            }
            actions.setResolvingId(proposalId, 'approve')
            try {
                // overwrite only replaces the draft the dialog warned about: the expected stamp fences
                // the write, so a draft that changed since returns 409 below.
                await hogFlowsProposalsApproveCreate(String(values.currentTeamIdStrict), props.id, proposalId, {
                    overwrite: true,
                    expected_draft_updated_at: expectedDraftUpdatedAt,
                })
                lemonToast.success('Suggestion staged as a draft. Publish it to go live.')
                workflowLogic({ id: props.id }).actions.loadWorkflow()
                actions.loadProposals()
            } catch (error) {
                if (error instanceof ApiError && error.status === 409) {
                    // The backend refuses a suggestion whose step list predates the live workflow, and
                    // says why. Its wording is more useful here than a generic draft-changed message.
                    lemonToast.error(
                        error.code === 'proposal_out_of_date' && error.detail
                            ? error.detail
                            : 'The staged draft changed while you were confirming. Review it and try again.'
                    )
                    workflowLogic({ id: props.id }).actions.loadWorkflow()
                    actions.loadProposals()
                } else {
                    lemonToast.error('Could not approve this suggestion. Please try again.')
                }
            } finally {
                actions.setResolvingId(null)
            }
        },
        rejectProposal: ({ proposalId }) => {
            if (values.resolvingId !== null) {
                return
            }
            LemonDialog.open({
                title: 'Reject this suggestion?',
                description: 'It stays in the workflow history as rejected. Nothing changes on the workflow.',
                primaryButton: {
                    children: 'Reject',
                    status: 'danger',
                    onClick: () => actions.confirmRejectProposal(proposalId),
                },
                secondaryButton: {
                    children: 'Cancel',
                },
            })
        },
        confirmRejectProposal: async ({ proposalId }) => {
            if (values.resolvingId !== null) {
                return
            }
            actions.setResolvingId(proposalId, 'reject')
            try {
                await hogFlowsProposalsRejectCreate(String(values.currentTeamIdStrict), props.id, proposalId, {})
                lemonToast.success('Suggestion rejected')
                actions.loadProposals()
            } catch {
                lemonToast.error('Could not reject this suggestion. Please try again.')
            } finally {
                actions.setResolvingId(null)
            }
        },
    })),
    listeners(({ actions, props, values }) => ({
        loadAppliedSuccess: () => {
            for (const proposal of values.appliedProposals) {
                if (!values.outcomes[proposal.id]) {
                    actions.loadOutcome(proposal.id)
                }
            }
        },
        loadOutcome: async ({ proposalId }) => {
            try {
                const outcome = await hogFlowsProposalsOutcomeRetrieve(
                    String(values.currentTeamIdStrict),
                    props.id,
                    proposalId
                )
                actions.setOutcome(proposalId, outcome)
            } catch {
                // A read-only retrospective card: a failed load just leaves it unrendered, no toast.
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadProposals()
        actions.loadApplied()
    }),
])
