// A file move queued while the file or its folder moves starts from the old path, so the shared tree caches the
// file there once both land.
function refuseMovingSource(
    items: FileSystemEntry[],
    folderMoving: (path: string) => string | null,
    pendingFileMoveIds: string[]
): boolean {
    if (items.some((item) => pendingFileMoveIds.includes(item.id))) {
        lemonToast.error("Couldn't move the file. Wait until it finishes moving.")
        return true
    }
    if (!items.some((item) => folderMoving(item.path))) {
        return false
    }
    lemonToast.error("Couldn't move the file. Wait until its folder finishes moving.")
    return true
}

/** The view loads no other product's files, so the server is asked whether one already sits at this path. */
async function isPathTaken(teamId: string, path: string, except?: string): Promise<boolean> {
    // A rename to the folder's current name matches the folder itself, so a second row is needed to find another file.
    const { results } = await withDeadline('checking a folder name', (signal) =>
        fileSystemList(teamId, { path, limit: 2 }, { signal })
    )
    return results.some((entry) => entry.id !== except)
}

function isIndexed(entry: FileSystemEntry): boolean {
    return entry.type === 'folder' || WORKFLOW_FILE_TYPES.includes(entry.type ?? '')
}

/** The last copy of each file the shared tree held, so a prune cannot drop it from the view. Moves and deletes update it, the folder scan replaces its folders and workflow files, and a file also leaves when its folder, still held and fully loaded, no longer lists it. */
function fileIndex(cache: Record<string, any>): Map<string, FileSystemEntry> {
    cache.fileIndex ??= new Map<string, FileSystemEntry>()
    return cache.fileIndex
}

/** Takes `gone` and everything inside a gone folder out of the file index. */
function forgetFiles(cache: Record<string, any>, gone: FileSystemEntry[]): void {
    cache.changes = (cache.changes ?? 0) + 1
    const ids = new Set(gone.map((item) => item.id))
    const folders = new Set(gone.filter((item) => item.type === 'folder').map((item) => joinPath(splitPath(item.path))))
    const index = fileIndex(cache)
    for (const [id, entry] of index) {
        if (ids.has(id) || ancestorFolders(entry.path).some((path) => folders.has(path))) {
            index.delete(id)
        }
    }
}

/** Makes a full scan the truth for the files `owns` selects: cached copies that moved or went away elsewhere leave the shared tree, and `scanned` replaces them in the file index. */
function applyFullScan(
    cache: Record<string, any>,
    entries: FileSystemEntry[],
    scanned: FileSystemEntry[],
    owns: (entry: FileSystemEntry) => boolean
): void {
    const freshPaths = new Map(scanned.map((entry) => [entry.id, entry.path]))
    const stale = Object.values(projectTreeDataLogic.values.folders)
        .flat()
        .filter((cached) => owns(cached) && !cached.shortcut && freshPaths.get(cached.id) !== cached.path)
    if (stale.length > 0) {
        projectTreeDataLogic.actions.dropStaleItems(stale)
    }
    projectTreeDataLogic.actions.addLoadedResults({
        searchTerm: '',
        results: entries,
        hasMore: false,
        lastCount: entries.length,
    })
    cache.fileIndex = new Map([
        ...[...fileIndex(cache)].filter(([, entry]) => !owns(entry)),
        ...scanned.map((entry): [string, FileSystemEntry] => [entry.id, entry]),
    ])
}

/** Each object's file keyed `type::ref`. A shortcut stands in only while the object's own file isn't loaded. */
function workflowFilesByRef(items: FileSystemEntry[]): Record<string, FileSystemEntry> {
    const filesByRef: Record<string, FileSystemEntry> = {}
    for (const item of items) {
        const key = `${item.type}::${item.ref}`
        if (item.type && item.ref && (!item.shortcut || !filesByRef[key])) {
            filesByRef[key] = item
        }
    }
    return filesByRef
}

/** Each workflow's file from the complete index, published only once a folder scan has filled it. */
function publishPlacements(
    cache: Record<string, any>,
    setPlacements: (placements: Record<string, FileSystemEntry>) => void
): void {
    if (cache.placementsKnown) {
        setPlacements(workflowFilesByRef([...fileIndex(cache).values()]))
    }
}

