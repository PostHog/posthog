const WORKFLOW_FILE_TYPES = ['hog_flow', 'message_template']

const MAX_INDEX_LOADS = 3

// A stalled request would leave the folders loading with no way to retry, so each one fails after this long.
export const FOLDER_REQUEST_TIMEOUT_MS = 10_000

const WORKFLOW_FILE_SEARCHES = ['type:folder', 'type:hog_flow', 'type:message_template']
const OTHER_FILES_SEARCH = '-type:folder -type:hog_flow -type:message_template'

async function listAllFiles(
    teamId: string,
    search: string,
    breakpoint: BreakPointFunction
): Promise<FileSystemEntry[]> {
    const entries: FileSystemEntry[] = []
    for (let offset = 0; ; offset += 500) {
        const page = await withTimeout(
            (signal) => fileSystemList(teamId, { search, limit: 500, offset }, { signal }),
            FOLDER_REQUEST_TIMEOUT_MS,
            'workflowFoldersLogic: listing project files timed out'
        )
        breakpoint()
        entries.push(
            ...page.results.map((entry) => ({
                id: entry.id,
                path: entry.path,
                type: entry.type,
                ref: entry.ref ?? undefined,
                href: entry.href ?? undefined,
                shortcut: entry.shortcut ?? false,
                created_at: entry.created_at,
                user_access_level: entry.user_access_level,
                team_id: entry.team_id,
                meta: entry.meta as FileSystemEntry['meta'],
            }))
        )
        if (!page.next || page.results.length === 0) {
            return entries
        }
    }
}

function changeCount(cache: Record<string, any>): number {
    return cache.changes ?? 0
}

function isIndexed(entry: FileSystemEntry): boolean {
    return entry.type === 'folder' || WORKFLOW_FILE_TYPES.includes(entry.type ?? '')
}

/** The last copy of each file the shared tree held, other products' files included, so a prune cannot turn their folders into empty workflow folders. Moves and deletes update it, the folder scan replaces its folders and workflow files, the other products' scan replaces the rest, and a file also leaves when its folder, still held and fully loaded, no longer lists it. */
function fileIndex(cache: Record<string, any>): Map<string, FileSystemEntry> {
    cache.fileIndex ??= new Map<string, FileSystemEntry>()
    return cache.fileIndex
}

/** Makes a full scan the truth for the files `owns` selects: cached copies that moved or went away elsewhere leave the shared tree, and `scanned` replaces them in the file index. */
function applyFullScan(
    cache: Record<string, any>,
    entries: FileSystemEntry[],
    scanned: FileSystemEntry[],
    owns: (entry: FileSystemEntry) => boolean
): void {
    const freshPaths = new Map(scanned.map((entry) => [entry.id, entry.path]))
    const stale = Object.values(projectTreeDataLogic.values.folders)
        .flat()
        .filter((cached) => owns(cached) && !cached.shortcut && freshPaths.get(cached.id) !== cached.path)
    if (stale.length > 0) {
        projectTreeDataLogic.actions.dropStaleItems(stale)
    }
    projectTreeDataLogic.actions.addLoadedResults({
        searchTerm: '',
        results: entries,
        hasMore: false,
        lastCount: entries.length,
    })
    cache.fileIndex = new Map([
        ...[...fileIndex(cache)].filter(([, entry]) => !owns(entry)),
        ...scanned.map((entry): [string, FileSystemEntry] => [entry.id, entry]),
    ])
}

/** Each workflow's file from the complete index, published only once a folder scan has filled it. */
function publishPlacements(
    cache: Record<string, any>,
    setPlacements: (placements: Record<string, FileSystemEntry>) => void
): void {
    if (cache.placementsKnown) {
        setPlacements(workflowFilesByRef([...fileIndex(cache).values()]))
    }
}

function treeFolderId(folder: string | null): string {
    return `project://${folder ?? ''}`
}

function ancestorFolders(path: string): string[] {
    const parts = splitPath(path)
    return parts.map((_, index) => joinPath(parts.slice(0, index + 1)))
}

function displayedParent(path: string): string {
    return displayedFolder(parentPath(path))
}

function isInScope(parent: string, folder: string | null, searching: boolean): boolean {
    const scope = folder ?? ''
    return searching ? !scope || parent === scope || parent.startsWith(`${scope}/`) : parent === scope
}

function relevantFolderPaths(items: FileSystemEntry[], hasUnfiledWorkflows: boolean): string[] {
    const files = items.filter((entry) => entry.type !== 'folder' && !entry.shortcut)
    const foldersWithFiles = new Set(files.flatMap((file) => ancestorFolders(parentPath(file.path))))
    const foldersWithWorkflowFiles = new Set(
        files
            .filter((file) => WORKFLOW_FILE_TYPES.includes(file.type ?? ''))
            .flatMap((file) => ancestorFolders(parentPath(file.path)))
    )
    const isRelevantEmptyFolder = (path: string): boolean => {
        const nearestFilledAncestor = ancestorFolders(parentPath(path))
            .reverse()
            .find((ancestor) => foldersWithFiles.has(ancestor))
        return !nearestFilledAncestor || foldersWithWorkflowFiles.has(nearestFilledAncestor)
    }
    const emptyFolders = items
        .filter(
            (entry) =>
                entry.type === 'folder' &&
                !entry.shortcut &&
                !entry.path.startsWith('Unfiled/') &&
                !foldersWithFiles.has(entry.path) &&
                isRelevantEmptyFolder(entry.path)
        )
        .map((entry) => entry.path)
    const paths = new Set(
        [...foldersWithWorkflowFiles, ...emptyFolders, ...(hasUnfiledWorkflows ? ['Unfiled'] : [])].flatMap((path) =>
            ancestorFolders(path === 'Unfiled' || path.startsWith('Unfiled/') ? 'Unfiled' : path)
        )
    )
    return [...paths].sort((a, b) => a.localeCompare(b))
}

