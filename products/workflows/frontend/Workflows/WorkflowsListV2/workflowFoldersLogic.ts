async function listAllFiles(
    teamId: string,
    search: string,
    breakpoint?: BreakPointFunction
): Promise<FileSystemEntry[]> {
    const entries: FileSystemEntry[] = []
    for (let offset = 0; ; offset += 500) {
        const page = await withDeadline('listing project files', (signal) =>
            fileSystemList(teamId, { search, limit: 500, offset }, { signal })
        )
        breakpoint?.()
        entries.push(
            ...page.results.map((entry) => ({
                id: entry.id,
                path: entry.path,
                type: entry.type,
                ref: entry.ref ?? undefined,
                href: entry.href ?? undefined,
                shortcut: entry.shortcut ?? false,
                created_at: entry.created_at,
                user_access_level: entry.user_access_level,
                team_id: entry.team_id,
                meta: entry.meta as FileSystemEntry['meta'],
            }))
        )
        if (!page.next || page.results.length === 0) {
            return entries
        }
    }
}

// A folder move is queued in two steps, a count check and then the move. The second step is queued in the same
// tick that clears the first, so the check waits for that tick before calling the move settled.
function whenSettled(isPending: () => boolean): Promise<void> {
    return new Promise((resolve) => {
        const settle = (): void => {
            if (!isPending()) {
                unsubscribe()
                resolve()
            }
        }
        const unsubscribe = getContext().store.subscribe(() => queueMicrotask(settle))
        settle()
    })
}

