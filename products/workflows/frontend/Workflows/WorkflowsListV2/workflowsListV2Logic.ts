export const workflowsListV2Logic = kea<workflowsListV2LogicType>([
    path(['products', 'workflows', 'frontend', 'workflowsListV2Logic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        loadList: true,
        setValue: (value: FacetSearchValue) => ({ value }),
        clearFilters: true,
        toggleColumn: (column: OptionalColumn) => ({ column }),
        resetColumns: true,
        patchWorkflow: (id: string, patch: Partial<HogFlowListRowApi>) => ({ id, patch }),
        removeRow: (id: string) => ({ id }),
        toggleWorkflowStatus: (row: WorkflowRow) => ({ row }),
        duplicateWorkflow: (row: WorkflowRow) => ({ row }),
        archiveWorkflow: (row: WorkflowRow) => ({ row }),
        restoreWorkflow: (row: WorkflowRow) => ({ row }),
        deleteWorkflow: (row: WorkflowRow) => ({ row }),
        duplicateTemplate: (row: EmailTemplateRow) => ({ row }),
        deleteTemplate: (row: EmailTemplateRow) => ({ row }),
    }),
    loaders(({ values, cache }) => ({
        listData: [
            null as WorkflowsListData | null,
            {
                loadList: async (_, breakpoint) => {
                    const projectId = String(values.currentProjectId)
                    const [workflows, templates] = await Promise.all([
                        loadAllPages((offset) =>
                            hogFlowsSummariesList(projectId, { type: WORKFLOWS_PAGE_TYPES, limit: PAGE_LIMIT, offset })
                        ),
                        loadAllPages((offset) =>
                            messagingTemplatesSummariesList(projectId, { limit: PAGE_LIMIT, offset })
                        ),
                    ])
                    breakpoint()
                    return { workflows, templates }
                },
            },
        ],
        serverSearch: [
            null as ServerSearchResult | null,
            {
                searchWorkflows: async (text: string, breakpoint) => {
                    await breakpoint(SERVER_SEARCH_DEBOUNCE_MS)
                    cache.searchAbort?.abort()
                    const controller = new AbortController()
                    cache.searchAbort = controller
                    const projectId = String(values.currentProjectId)
                    try {
                        const workflows = await loadAllPages((offset) =>
                            hogFlowsSummariesList(
                                projectId,
                                { type: WORKFLOWS_PAGE_TYPES, search: text, limit: PAGE_LIMIT, offset },
                                { signal: controller.signal }
                            )
                        )
                        breakpoint()
                        return { text, ids: workflows.map((workflow) => workflow.id) }
                    } catch (error) {
                        // A newer search aborted this one; drop it quietly.
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        value: [
            EMPTY_VALUE,
            {
                setValue: (_, { value }) => value,
                clearFilters: () => EMPTY_VALUE,
            },
        ],
        loadFailed: [
            false,
            {
                loadList: () => false,
                loadListSuccess: () => false,
                loadListFailure: () => true,
            },
        ],
        visibleColumns: [
            [] as OptionalColumn[],
            { persist: true },
            {
                toggleColumn: (state, { column }) =>
                    state.includes(column)
                        ? state.filter((c) => c !== column)
                        : OPTIONAL_COLUMNS.filter((c) => c === column || state.includes(c)),
                resetColumns: () => [],
            },
        ],
        listData: {
            patchWorkflow: (state, { id, patch }) =>
                state && {
                    ...state,
                    workflows: state.workflows.map((workflow) =>
                        workflow.id === id ? { ...workflow, ...patch } : workflow
                    ),
                },
            removeRow: (state, { id }) =>
                state && {
                    workflows: state.workflows.filter((workflow) => workflow.id !== id),
                    templates: state.templates.filter((template) => template.id !== id),
                },
        },
    }),
    selectors({
        rows: [
            (s) => [s.listData],
            (listData: WorkflowsListData | null): WorkflowListRow[] =>
                listData ? buildWorkflowListRows(listData.workflows, listData.templates) : [],
        ],
        listLoaded: [(s) => [s.listData], (listData: WorkflowsListData | null): boolean => listData !== null],
        facets: [
            (s) => [s.rows],
            (rows: WorkflowListRow[]): FacetDefinition<WorkflowListRow>[] => buildWorkflowListFacets(rows),
        ],
        matchesText: [
            (s) => [s.serverSearch],
            (serverSearch: ServerSearchResult | null): MatchesText<WorkflowListRow> => {
                const serverIds = new Set(serverSearch?.ids ?? [])
                // The server also searches email bodies and preheaders, which the slim rows don't carry.
                return (row, text) =>
                    matchesWorkflowListText(row, text) ||
                    (row.kind === 'workflow' && serverSearch?.text === text.trim() && serverIds.has(row.id))
            },
        ],
        filteredRows: [
            (s) => [s.rows, s.value, s.facets, s.matchesText],
            (
                rows: WorkflowListRow[],
                value: FacetSearchValue,
                facets: FacetDefinition<WorkflowListRow>[],
                matchesText: MatchesText<WorkflowListRow>
            ): WorkflowListRow[] => rows.filter((row) => matchesFacetQuery(row, value, facets, matchesText)),
        ],
        hasActiveFilters: [
            (s) => [s.value],
            (value: FacetSearchValue): boolean => value.filters.length > 0 || value.text.trim() !== '',
        ],
    }),
    listeners(({ actions, values }) => ({
        setValue: ({ value }) => {
            const text = value.text.trim()
            if (text.length >= MIN_SERVER_SEARCH_LENGTH && values.serverSearch?.text !== text) {
                actions.searchWorkflows(text)
            }
        },
        loadListFailure: ({ error }) => {
            lemonToast.error(`Failed to load workflows: ${error || 'Unknown error'}`)
        },
        toggleWorkflowStatus: async ({ row }) => {
            const status = row.workflow.status === 'active' ? 'draft' : 'active'
            try {
                await api.hogFlows.updateHogFlow(row.id, { status })
                actions.patchWorkflow(row.id, { status })
            } catch (error) {
                lemonToast.error(`Failed to update workflow: ${errorDetail(error)}`)
            }
        },
        duplicateWorkflow: async ({ row }) => {
            try {
                // The slim row has no step graph, so the copy starts from the full workflow.
                const full = await hogFlowsRetrieve(String(values.currentProjectId), row.id)
                await api.hogFlows.createHogFlow(prepareWorkflowDuplicate(full as unknown as HogFlow))
                lemonToast.success(`Workflow "${row.name}" duplicated`)
                actions.loadList()
            } catch (error) {
                lemonToast.error(`Failed to duplicate workflow: ${errorDetail(error)}`)
            }
        },
        archiveWorkflow: ({ row }) => {
            LemonDialog.open({
                width: 500,
                title: 'Archive workflow?',
                description: `Are you sure you want to archive "${row.name}"?${
                    row.workflow.status === 'active'
                        ? ' In-progress workflow invocations will end without completing.'
                        : ''
                }`,
                primaryButton: {
                    children: 'Archive',
                    type: 'primary',
                    status: 'danger',
                    onClick: async () => {
                        try {
                            await api.hogFlows.updateHogFlow(row.id, { status: 'archived' })
                            lemonToast.success(`Workflow "${row.name}" archived`)
                            actions.patchWorkflow(row.id, { status: 'archived' })
                        } catch (error) {
                            lemonToast.error(`Failed to archive workflow: ${errorDetail(error)}`)
                        }
                    },
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        restoreWorkflow: async ({ row }) => {
            try {
                await api.hogFlows.updateHogFlow(row.id, { status: 'draft' })
                lemonToast.success(`Workflow "${row.name}" restored to draft status`)
                actions.patchWorkflow(row.id, { status: 'draft' })
            } catch (error) {
                lemonToast.error(`Failed to restore workflow: ${errorDetail(error)}`)
            }
        },
        deleteWorkflow: ({ row }) => {
            LemonDialog.open({
                width: 500,
                title: 'Delete workflow?',
                description: `Are you sure you want to permanently delete "${row.name}"? This action cannot be undone.`,
                primaryButton: {
                    children: 'Delete',
                    type: 'primary',
                    status: 'danger',
                    onClick: async () => {
                        try {
                            await api.hogFlows.deleteHogFlow(row.id)
                            lemonToast.success(`Workflow "${row.name}" deleted`)
                            deleteFromTree('hog_flow/', row.id)
                            actions.removeRow(row.id)
                        } catch (error) {
                            lemonToast.error(`Failed to delete workflow: ${errorDetail(error)}`)
                        }
                    },
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
        duplicateTemplate: async ({ row }) => {
            const projectId = String(values.currentProjectId)
            try {
                // The slim row has no content, so the copy starts from the full template.
                const full = await messagingTemplatesRetrieve(projectId, row.id)
                await messagingTemplatesCreate(projectId, {
                    name: `${full.name} (copy)`,
                    description: full.description,
                    content: full.content,
                })
                lemonToast.success('Template duplicated successfully')
                actions.loadList()
            } catch {
                lemonToast.error('Failed to duplicate template')
            }
        },
        deleteTemplate: async ({ row }) => {
            await deleteWithUndo({
                endpoint: `projects/${values.currentProjectId}/messaging_templates`,
                object: { id: row.id, name: row.name },
                callback: (undo) => {
                    if (undo) {
                        actions.loadList()
                    }
                },
            })
            actions.removeRow(row.id)
        },
    })),
    actionToUrl(({ values }) => {
        const writeUrl = (): [string, Record<string, string>, Record<string, any>, { replace: boolean }] => {
            const searchParams: Record<string, string> = { ...router.values.searchParams }
            const q = serializeFacetQuery(values.value.filters)
            const text = values.value.text.trim()
            delete searchParams.q
            delete searchParams.text
            if (q) {
                searchParams.q = q
            }
            if (text) {
                searchParams.text = text
            }
            return [router.values.location.pathname, searchParams, router.values.hashParams, { replace: true }]
        }
        return { setValue: writeUrl, clearFilters: writeUrl }
    }),
    urlToAction(({ actions, values }) => ({
        [urls.workflows()]: (_, searchParams, hashParams) => {
            if (LEGACY_PARAMS.some((param) => param in searchParams)) {
                const legacy = legacyParamsToValue(searchParams)
                const current: FacetSearchValue = {
                    filters: parseFacetQuery(String(searchParams.q ?? ''), QUERY_FACETS),
                    text: String(searchParams.text ?? ''),
                }
                const next: Record<string, unknown> = { ...searchParams }
                for (const param of LEGACY_PARAMS) {
                    delete next[param]
                }
                const q = serializeFacetQuery([...current.filters, ...legacy.filters])
                const text = current.text || legacy.text
                delete next.q
                delete next.text
                if (q) {
                    next.q = q
                }
                if (text) {
                    next.text = text
                }
                router.actions.replace(urls.workflows(), next, hashParams)
                return
            }
            const value: FacetSearchValue = {
                filters: parseFacetQuery(String(searchParams.q ?? ''), QUERY_FACETS),
                text: String(searchParams.text ?? ''),
            }
            if (
                serializeFacetQuery(value.filters) !== serializeFacetQuery(values.value.filters) ||
                value.text !== values.value.text
            ) {
                actions.setValue(value)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadList()
    }),
])
