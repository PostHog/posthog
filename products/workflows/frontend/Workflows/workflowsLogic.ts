export const workflowsLogic = kea<workflowsLogicType>([
    key(() => 'workflowsLogic'),
    path(['products', 'workflows', 'frontend', 'workflowsLogic']),
    connect(() => ({
        values: [tagsModel, ['tags']],
        actions: [tagsModel, ['loadTags', 'loadTagsIfNeeded']],
    })),
    actions({
        toggleWorkflowStatus: (workflow: HogFlow) => ({ workflow }),
        duplicateWorkflow: (workflow: HogFlow) => ({ workflow }),
        archiveWorkflow: (workflow: HogFlow) => ({ workflow }),
        restoreWorkflow: (workflow: HogFlow) => ({ workflow }),
        deleteWorkflow: (workflow: HogFlow) => ({ workflow }),
        deleteSelectedWorkflows: true,
        loadWorkflows: () => ({}),
        setFilters: (filters: Partial<WorkflowsFilters>, replace?: boolean) => ({ filters, replace }),
        selectTypeTab: (type: WorkflowTypeFilter) => ({ type }),
        toggleArchivedWorkflowSelection: (id: string) => ({ id }),
        selectAllArchivedWorkflows: (ids: string[]) => ({ ids }),
        clearArchivedWorkflowSelection: true,
        updateWorkflowTags: (workflow: HogFlow, tags: string[]) => ({ workflow, tags }),
        setSavedWorkflowTags: (id: string, tags: string[]) => ({ id, tags }),
        setTagsFilter: (tags: string[], source: 'filter' | 'tag_click') => ({ tags, source }),
    }),
    reducers(() => ({
        filters: [
            DEFAULT_FILTERS,
            // The list unmounts when a workflow opens, so the filters are persisted to survive that and
            // be restored when the user comes back to the list. The key carries the user and the team, so
            // another account or another project never reads these filters.
            buildUserScopedPersistenceConfig('workflows_list_filters__'),
            {
                setFilters: (state, { filters, replace }) => {
                    const next = replace ? { ...DEFAULT_FILTERS, ...filters } : { ...state, ...filters }
                    // Any filter change other than paging jumps back to the first page, so results stay
                    // in sync with what the user just typed/picked.
                    if (!('page' in filters)) {
                        next.page = 1
                    }
                    return next
                },
            },
        ],
        selectedArchivedWorkflowIds: [
            new Set<string>(),
            {
                toggleArchivedWorkflowSelection: (state, { id }) => {
                    const next = new Set(state)
                    if (next.has(id)) {
                        next.delete(id)
                    } else {
                        next.add(id)
                    }
                    return next
                },
                selectAllArchivedWorkflows: (_, { ids }) => new Set<string>(ids),
                clearArchivedWorkflowSelection: () => new Set<string>(),
                loadWorkflowsSuccess: () => new Set<string>(),
            },
        ],
        hasLoadedWorkflows: [
            false as boolean,
            {
                loadWorkflowsSuccess: () => true,
            },
        ],
        // Tags edited in a row show at once, before the save returns. A reload brings the saved tags.
        localWorkflowTags: [
            {} as Record<string, string[]>,
            {
                updateWorkflowTags: (state, { workflow, tags }) => ({ ...state, [workflow.id]: tags }),
                setSavedWorkflowTags: (state, { id, tags }) => ({ ...state, [id]: tags }),
                loadWorkflowsSuccess: () => ({}),
            },
        ],
    })),
    loaders(({ actions, values }) => ({
        workflows: [
            { results: [], count: 0 } as WorkflowsResult,
            {
                loadWorkflows: async (_, breakpoint) => {
                    const response = await api.hogFlows.getHogFlows(values.paramsFromFilters)
                    // Drop a response a newer filter change has already superseded, so a slow request
                    // returning after a faster later one can't leave the table showing the wrong filters.
                    breakpoint()
                    return response
                },
                toggleWorkflowStatus: async ({ workflow }) => {
                    await api.hogFlows.updateHogFlow(workflow.id, {
                        status: workflow.status === 'active' ? 'draft' : 'active',
                    })
                    // Reload instead of patching in place: the new status may no longer match the
                    // active status filter, so the row has to be re-fetched through the server query.
                    actions.loadWorkflows()
                    return values.workflows
                },
                duplicateWorkflow: async ({ workflow }) => {
                    await api.hogFlows.createHogFlow(prepareWorkflowDuplicate(workflow))
                    // The copy is a draft; reload so it only shows when it matches the current filter
                    // and lands in the right spot under the server-side sort and pagination.
                    actions.loadWorkflows()
                    return values.workflows
                },
                archiveWorkflow: async ({ workflow }) => {
                    LemonDialog.open({
                        width: 500,
                        title: 'Archive workflow?',
                        description: `Are you sure you want to archive "${workflow.name}"?${
                            workflow.status === 'active'
                                ? ' In-progress workflow invocations will end without completing.'
                                : ''
                        }`,
                        primaryButton: {
                            children: 'Archive',
                            type: 'primary',
                            status: 'danger',
                            onClick: async () => {
                                try {
                                    await api.hogFlows.updateHogFlow(workflow.id, {
                                        status: 'archived',
                                    })
                                    lemonToast.success(`Workflow "${workflow.name}" archived`)
                                    router.actions.push(urls.workflows())
                                    actions.loadWorkflows()
                                } catch (error: any) {
                                    lemonToast.error(
                                        `Failed to archive workflow: ${error.detail || error.message || 'Unknown error'}`
                                    )
                                }
                            },
                        },
                        secondaryButton: {
                            children: 'Cancel',
                        },
                    })
                    // Return unchanged workflows since dialog handles the update
                    return values.workflows
                },
                restoreWorkflow: async ({ workflow }) => {
                    try {
                        await api.hogFlows.updateHogFlow(workflow.id, {
                            status: 'draft',
                        })
                        lemonToast.success(`Workflow "${workflow.name}" restored to draft status`)
                        // Restored workflows become drafts, so they drop out of the archived filter —
                        // reload rather than keep the stale row in the current filtered page.
                        actions.loadWorkflows()
                        return values.workflows
                    } catch (error: any) {
                        lemonToast.error(
                            `Failed to restore workflow: ${error?.detail || error?.message || 'Unknown error'}`
                        )
                        return values.workflows
                    }
                },
                deleteWorkflow: async ({ workflow }) => {
                    LemonDialog.open({
                        width: 500,
                        title: 'Delete workflow?',
                        description: `Are you sure you want to permanently delete "${workflow.name}"? This action cannot be undone.`,
                        primaryButton: {
                            children: 'Delete',
                            type: 'primary',
                            status: 'danger',
                            onClick: async () => {
                                try {
                                    await api.hogFlows.deleteHogFlow(workflow.id)
                                    lemonToast.success(`Workflow "${workflow.name}" deleted`)
                                    deleteFromTree('hog_flow/', workflow.id)
                                    actions.loadWorkflows()
                                } catch (error: any) {
                                    lemonToast.error(
                                        `Failed to delete workflow: ${error.detail || error.message || 'Unknown error'}`
                                    )
                                }
                            },
                        },
                        secondaryButton: {
                            children: 'Cancel',
                        },
                    })
                    return values.workflows
                },
            },
        ],
    })),
    selectors({
        paramsFromFilters: [
            (s) => [s.filters],
            (filters: WorkflowsFilters): WorkflowsListParams => ({
                search: filters.search || undefined,
                status: filters.status !== 'all' ? filters.status : undefined,
                created_by: filters.createdBy || undefined,
                // Name the types this page covers rather than the one it hides, so a surface that
                // grows its own page drops out here instead of every list learning to exclude it.
                // Server-side keeps `count` honest, which dropping rows from the page did not.
                type: filters.type !== 'all' ? [filters.type] : WORKFLOWS_PAGE_TYPES,
                // The API filters triggers by JSON containment, so the type goes over as a JSON object.
                trigger: filters.triggerType !== 'all' ? JSON.stringify({ type: filters.triggerType }) : undefined,
                tags: filters.tags.length ? JSON.stringify(filters.tags) : undefined,
                // Only this page sorts a waiting suggestion above recency; every other reader of the
                // list keeps recency, so one stale workflow cannot push fresh ones off their first page.
                suggestions_first: true,
                limit: WORKFLOWS_PER_PAGE,
                offset: filters.page ? (filters.page - 1) * WORKFLOWS_PER_PAGE : 0,
            }),
        ],
        pagination: [
            (s) => [s.filters, s.workflows],
            (filters: WorkflowsFilters, workflows: WorkflowsResult): PaginationManual => ({
                controlled: true,
                pageSize: WORKFLOWS_PER_PAGE,
                currentPage: filters.page || 1,
                entryCount: workflows.count,
            }),
        ],
        allArchivedSelected: [
            (s) => [s.workflows, s.selectedArchivedWorkflowIds],
            (workflows: WorkflowsResult, selectedIds: Set<string>): boolean => {
                return workflows.results.length > 0 && workflows.results.every((w) => selectedIds.has(w.id))
            },
        ],
        selectedArchivedCount: [
            (s) => [s.selectedArchivedWorkflowIds],
            (selectedIds: Set<string>): number => selectedIds.size,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        selectTypeTab: ({ type }) => {
            actions.setFilters({ type })
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows type tab selected', { type })
        },
        setFilters: async (_, breakpoint) => {
            // Debounce so typing in the search box doesn't fire a request per keystroke.
            await breakpoint(300)
            actions.loadWorkflows()
        },
        setTagsFilter: ({ tags, source }) => {
            actions.setFilters({ tags })
            posthog.capture('workflows tag filter changed', { tags_count: tags.length, source })
        },
        updateWorkflowTags: async ({ workflow, tags }) => {
            // Every pick in the open picker saves the whole list, so chain a workflow's saves: an
            // earlier list landing last would drop the tags picked after it.
            const pending: Record<string, Promise<void>> = cache.tagSaves ?? (cache.tagSaves = {})
            const save = (pending[workflow.id] ?? Promise.resolve()).then(async () => {
                // Only the tags go over the wire, so a row edit never touches the workflow's content.
                const saved = await hogFlowsPartialUpdate(String(ApiConfig.getCurrentTeamId()), workflow.id, { tags })
                posthog.capture('workflow tags updated', { source: 'workflows_list', tags_count: tags.length })
                // The server lowercases and trims each name, so show what it stored, not what was typed.
                actions.setSavedWorkflowTags(workflow.id, saved.tags ? [...saved.tags] : tags)
                actions.loadTags()
            })
            pending[workflow.id] = save.catch(() => {})
            try {
                await save
            } catch (error: any) {
                lemonToast.error(`Failed to save tags: ${error?.detail || error?.message || 'Unknown error'}`)
                actions.loadWorkflows()
            }
        },
        loadWorkflowsSuccess: ({ workflows }) => {
            // A page past the end (stale link, or rows deleted since) would otherwise leave the user on a
            // blank table with no pagination control to click back with, so land them on the last real page.
            const lastPage = Math.max(1, Math.ceil(workflows.count / WORKFLOWS_PER_PAGE))
            if (values.filters.page > lastPage) {
                actions.setFilters({ page: lastPage })
            }
        },
        loadWorkflowsFailure: ({ error }) => {
            lemonToast.error(`Failed to load workflows: ${error || 'Unknown error'}`)
        },
        deleteSelectedWorkflows: () => {
            const ids = Array.from(values.selectedArchivedWorkflowIds)
            if (ids.length === 0) {
                return
            }
            LemonDialog.open({
                width: 500,
                title: `Delete ${ids.length} archived workflow${ids.length === 1 ? '' : 's'}?`,
                description: `Are you sure you want to permanently delete ${ids.length} archived workflow${ids.length === 1 ? '' : 's'}? This action cannot be undone.`,
                primaryButton: {
                    children: 'Delete',
                    type: 'primary',
                    status: 'danger',
                    onClick: async () => {
                        try {
                            const result = await api.hogFlows.bulkDeleteHogFlows(ids)
                            lemonToast.success(`${result.deleted} workflow${result.deleted === 1 ? '' : 's'} deleted`)
                            for (const id of ids) {
                                deleteFromTree('hog_flow/', id)
                            }
                            actions.clearArchivedWorkflowSelection()
                            actions.loadWorkflows()
                        } catch (error: any) {
                            lemonToast.error(
                                `Failed to delete workflows: ${error?.detail || error?.message || 'Unknown error'}`
                            )
                        }
                    },
                },
                secondaryButton: {
                    children: 'Cancel',
                },
            })
        },
    })),
    actionToUrl(({ values }) => {
        const buildURL = (): [string, Record<string, any>, Record<string, any>, { replace: boolean }] => {
            const searchParams = { ...router.values.searchParams }

            const setOrDelete = (key: string, value: string | number | string[] | null | undefined): void => {
                if (value) {
                    searchParams[key] = value
                } else {
                    delete searchParams[key]
                }
            }

            setOrDelete('search', values.filters.search)
            setOrDelete('created_by', values.filters.createdBy)
            setOrDelete('status', values.filters.status !== 'all' ? values.filters.status : null)
            setOrDelete('type', values.filters.type !== 'all' ? values.filters.type : null)
            setOrDelete('trigger_type', values.filters.triggerType !== 'all' ? values.filters.triggerType : null)
            setOrDelete('tags', values.filters.tags.length ? values.filters.tags : null)
            setOrDelete('page', values.filters.page > 1 ? values.filters.page : null)

            return [router.values.location.pathname, searchParams, router.values.hashParams, { replace: true }]
        }

        return {
            setFilters: buildURL,
        }
    }),
    urlToAction(({ actions, values }) => {
        const syncFiltersFromUrl = (_: Record<string, any>, searchParams: Record<string, any>): void => {
            // An in-app link back to the list, such as the breadcrumb out of a workflow, carries no filter
            // params. Parsing that URL would clear every filter, so the filters held in state are restored
            // and written back into the URL instead.
            if (!FILTER_URL_PARAMS.some((param) => param in searchParams)) {
                if (!objectsEqual(values.filters, DEFAULT_FILTERS)) {
                    actions.setFilters(values.filters)
                }
                return
            }
            const status = searchParams['status']
            const type = searchParams['type']
            const triggerType = searchParams['trigger_type']
            const tags = searchParams['tags']
            const parsed: WorkflowsFilters = {
                search: searchParams['search'] ? String(searchParams['search']) : '',
                createdBy: searchParams['created_by'] ? String(searchParams['created_by']) : null,
                status: WORKFLOW_STATUS_FILTERS.includes(status) ? status : 'all',
                type: WORKFLOW_TYPE_FILTERS.includes(type) ? type : 'all',
                triggerType: WORKFLOW_TRIGGER_TYPE_FILTERS.includes(triggerType) ? triggerType : 'all',
                // kea-router parses a JSON array in the URL back into an array.
                tags: Array.isArray(tags) ? tags.map(String) : typeof tags === 'string' && tags ? [tags] : [],
                // Anything unparseable, zero, or negative falls back to page 1 rather than reaching
                // the offset maths as NaN or a negative number.
                page: Math.max(1, parseInt(String(searchParams['page'])) || 1),
            }
            if (!objectsEqual(parsed, values.filters)) {
                actions.setFilters(parsed, true)
            }
        }
        // The list renders on both the bare scene URL and its explicit tab URL, so shared links work from either.
        return {
            [urls.workflows()]: syncFiltersFromUrl,
            [urls.workflows('workflows')]: syncFiltersFromUrl,
        }
    }),
])
