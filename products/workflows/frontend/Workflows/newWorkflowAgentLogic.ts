// pinned: MCP tool name from products/workflows/mcp/tools.yaml
const CREATE_WORKFLOW_TOOL = 'workflows-create'

/**
 * The id of the draft a `workflows-create` call just made. The call's output is not usable for this: a
 * workflow with rendered email HTML exceeds the harness's tool-result limit, and the frontend only sees
 * the "saved to file" notice. The list is newest-first, so the first workflow with the name the agent
 * sent is the one it created; without a usable name, the newest workflow is taken.
 */
export async function findCreatedWorkflowId(name: unknown): Promise<string | null> {
    const search = typeof name === 'string' && name.trim() ? name.trim() : undefined
    const { results } = await api.hogFlows.getHogFlows({ search, limit: 5 })
    const match = search ? results.find((workflow) => workflow.name === search) : results[0]
    return match?.id ?? null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newWorkflowAgentLogicValues {
    activeCreation: ActiveCreation | null // runnerPanelLogic
    selectedTab: SidePanelTab | null // sidePanelStateLogic
    sidePanelOpen: boolean // sidePanelStateLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newWorkflowAgentLogicActions {
    clearActiveCreation: () => {
        value: true
    } // runnerPanelLogic
    setActiveCreation: (creation: ActiveCreation) => {
        creation: ActiveCreation
    } // runnerPanelLogic
    setHistoryExpanded: (expanded: boolean) => {
        expanded: boolean
    } // runnerPanelLogic
    closeSidePanel: (tab?: SidePanelTab | undefined) => {
        tab: SidePanelTab | undefined
    } // sidePanelStateLogic
    openSidePanel: (
        tab: SidePanelTab,
        options?: string | undefined
    ) => {
        options: string | undefined
        tab: SidePanelTab
    } // sidePanelStateLogic
    emitToolEvent: (event: ToolStreamEvent) => {
        event: ToolStreamEvent
    } // toolStreamEventsLogic
    setSeed: (seed: ComposerSeed) => {
        seed: ComposerSeed
    } // composerSeedLogic
    composerShown: () => {
        value: true
    }
}

export type newWorkflowAgentLogicType = MakeLogicType<newWorkflowAgentLogicValues, newWorkflowAgentLogicActions>

/**
 * Drives the AI-first "New workflow" screen. The composer on that screen is the PostHog AI side panel's own
 * runner instance, so the run never has to be handed over: once the agent's `workflows-create` call completes,
 * this opens the side panel (which keeps that instance mounted across the route change) and routes to the
 * new draft, where the panel continues the same thread against the open editor.
 */
export const newWorkflowAgentLogic = kea<newWorkflowAgentLogicType>([
    path(['products', 'workflows', 'frontend', 'newWorkflowAgentLogic']),
    connect(() => ({
        values: [
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['activeCreation'],
            sidePanelStateLogic,
            ['sidePanelOpen', 'selectedTab'],
        ],
        actions: [
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setActiveCreation', 'clearActiveCreation', 'setHistoryExpanded'],
            sidePanelStateLogic,
            ['openSidePanel', 'closeSidePanel'],
            toolStreamEventsLogic,
            ['emitToolEvent'],
            composerSeedLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setSeed'],
        ],
    })),
    actions({
        composerShown: true,
    }),
    listeners(({ actions, cache, values }) => ({
        // Dispatched from the component's mount effect, after the previous scene has left the panel
        // registry: a close fired earlier would count as the user dismissing the editor's auto-open.
        composerShown: () => {
            // The panel is shared with the PostHog AI side panel: a run or history list left open there must
            // not take the place of the composer, and a second copy of it beside the page is noise.
            actions.clearActiveCreation()
            actions.setHistoryExpanded(false)
            // A prompt typed in the panel and never sent is still in the shared form, where it would greet
            // the person under the new-workflow headline. An empty seed is how a host prefills this
            // composer, so it is also how a host empties it.
            actions.setSeed({ prompt: '', autoSubmit: false })
            if (values.sidePanelOpen && values.selectedTab === SidePanelTab.Max) {
                actions.closeSidePanel()
            }
            posthog.capture('workflow ai composer viewed')
        },
        setActiveCreation: ({ creation }, _breakpoint, _action, previousState) => {
            // The first set for a stream key is the send; later ones attach the task and run ids.
            const previous = runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }).selectors.activeCreation(previousState)
            if (previous?.streamKey !== creation.streamKey) {
                posthog.capture('workflow ai composer submitted')
            }
        },
        emitToolEvent: async ({ event }) => {
            if (
                event.source !== 'live' ||
                event.phase !== 'completed' ||
                event.toolName !== CREATE_WORKFLOW_TOOL ||
                event.streamKey !== values.activeCreation?.streamKey ||
                cache.handedOff
            ) {
                return
            }
            let workflowId: string | null = null
            try {
                workflowId = await findCreatedWorkflowId(resolveToolCall(event.invocation).innerInput?.name)
            } catch {
                // A rejected list call (a network failure, or a name the search endpoint refuses) reads the
                // same to the person as a name that matches nothing: the draft is saved and this page cannot
                // open it. Both leave the run on screen, so the thread continues either way.
                workflowId = null
            }
            if (cache.handedOff) {
                return
            }
            if (!workflowId) {
                lemonToast.error(
                    'Your workflow was created, but it could not be opened. Find it in the workflows list.'
                )
                return
            }
            cache.handedOff = true
            posthog.capture('workflow ai composer created workflow', { workflow_id: workflowId })
            // Open the panel before leaving the page so the runner instance stays mounted with its run.
            actions.openSidePanel(SidePanelTab.Max)
            router.actions.push(urls.workflow(workflowId, 'workflow'))
        },
    })),
])
