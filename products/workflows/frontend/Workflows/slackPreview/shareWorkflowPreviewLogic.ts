export const shareWorkflowPreviewLogic = kea<shareWorkflowPreviewLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'slackPreview', 'shareWorkflowPreviewLogic', key]),
    props({} as ShareWorkflowPreviewLogicProps),
    key((props) => props.id),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], integrationsLogic, ['integrations', 'slackIntegrations']],
    })),
    actions({
        openModal: (workflow: HogFlow) => ({ workflow }),
        closeModal: true,
        setIntegrationId: (integrationId: number | null) => ({ integrationId }),
        setChannel: (channel: string | null) => ({ channel }),
        setThreadLink: (threadLink: string) => ({ threadLink }),
        setNote: (note: string) => ({ note }),
        toggleEmail: (actionId: string) => ({ actionId }),
        submit: true,
        submitSuccess: (destination: string) => ({ destination }),
        submitFailure: (reason: string, detail: string) => ({ reason, detail }),
    }),
    reducers({
        workflow: [null as HogFlow | null, { openModal: (_, { workflow }) => workflow }],
        isOpen: [false, { openModal: () => true, closeModal: () => false, submitSuccess: () => false }],
        integrationId: [null as number | null, { setIntegrationId: (_, { integrationId }) => integrationId }],
        channel: [null as string | null, { setChannel: (_, { channel }) => channel, setIntegrationId: () => null }],
        threadLink: ['', { setThreadLink: (_, { threadLink }) => threadLink, submitSuccess: () => '' }],
        note: ['', { setNote: (_, { note }) => note, submitSuccess: () => '' }],
        excludedEmailIds: [
            [] as string[],
            {
                toggleEmail: (excluded, { actionId }) =>
                    excluded.includes(actionId) ? excluded.filter((id) => id !== actionId) : [...excluded, actionId],
                openModal: () => [],
            },
        ],
        isSubmitting: [false, { submit: () => true, submitSuccess: () => false, submitFailure: () => false }],
    }),
    selectors({
        emailSendersByIntegrationId: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): EmailSendersByIntegrationId =>
                Object.fromEntries(
                    (integrations ?? [])
                        .filter((integration) => integration.kind === 'email')
                        .map((integration) => [
                            integration.id,
                            { name: integration.config?.name, email: integration.config?.email },
                        ])
                ),
        ],
        emailSteps: [
            (s) => [s.workflow, s.emailSendersByIntegrationId],
            (workflow: HogFlow | null, senders: EmailSendersByIntegrationId): EmailStep[] =>
                workflow ? listEmailSteps(workflow, senders) : [],
        ],
        selectedEmailSteps: [
            (s) => [s.emailSteps, s.excludedEmailIds],
            (emailSteps: EmailStep[], excludedEmailIds: string[]): EmailStep[] =>
                emailSteps.filter((step) => !excludedEmailIds.includes(step.actionId)),
        ],
        selectedSlackIntegration: [
            (s) => [s.slackIntegrations, s.integrationId],
            (slackIntegrations: IntegrationType[] | undefined, integrationId: number | null): IntegrationType | null =>
                slackIntegrations?.find((integration) => integration.id === integrationId) ?? null,
        ],
        canUploadImages: [
            (s) => [s.selectedSlackIntegration],
            (integration: IntegrationType | null): boolean =>
                !integration || getGrantedScopes(integration).includes('files:write'),
        ],
        submitDisabledReason: [
            (s) => [s.integrationId, s.channel, s.threadLink, s.selectedEmailSteps, s.canUploadImages],
            (
                integrationId: number | null,
                channel: string | null,
                threadLink: string,
                selectedEmailSteps: EmailStep[],
                canUploadImages: boolean
            ): string | undefined =>
                getShareDisabledReason({
                    integrationId,
                    channel,
                    threadLink,
                    selectedEmailCount: selectedEmailSteps.length,
                    canUploadImages,
                }),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        submit: async () => {
            const { integrationId, channel, threadLink, note, workflow, selectedEmailSteps, currentProjectId } = values
            if (!integrationId || !currentProjectId || !workflow) {
                actions.submitFailure('incomplete_form', 'Select a Slack workspace and a channel first.')
                return
            }
            const emails: { title: string; image_base64: string }[] = []
            for (const step of selectedEmailSteps) {
                const title = emailTitle(step)
                let imageBase64: string
                try {
                    imageBase64 = await renderEmailPreviewPngBase64(step)
                } catch {
                    actions.submitFailure(
                        'render_failed',
                        `Couldn't render the email "${title}". Deselect it, or try again.`
                    )
                    return
                }
                if (decodedSize(imageBase64) > MAX_IMAGE_BYTES) {
                    actions.submitFailure(
                        'image_too_large',
                        `The email "${title}" is too large to share as an image. Deselect it to share the rest.`
                    )
                    return
                }
                emails.push({ title: clip(title, MAX_CAPTION_LENGTH), image_base64: imageBase64 })
            }
            const sharesIntoThread = !!threadLink.trim()
            try {
                await hogFlowsSharePreviewToSlack(String(currentProjectId), props.id, {
                    integration_id: integrationId,
                    channel,
                    thread_link: threadLink.trim() || null,
                    note,
                    outline: buildWorkflowOutline(workflow).map((line) => clip(line, MAX_OUTLINE_LINE_LENGTH)),
                    emails,
                })
            } catch (e) {
                actions.submitFailure(
                    'slack_rejected',
                    (e instanceof ApiError && e.detail) || "Couldn't share the preview to Slack. Try again."
                )
                return
            }
            posthog.capture('workflow preview shared to slack', {
                email_count: emails.length,
                destination: sharesIntoThread ? 'thread' : 'channel',
            })
            actions.submitSuccess(sharesIntoThread ? 'the Slack thread' : slackChannelDisplayName(channel ?? ''))
        },
        submitSuccess: ({ destination }) => {
            lemonToast.success(`Preview shared to ${destination}`)
        },
        submitFailure: ({ reason, detail }) => {
            posthog.capture('workflow preview share to slack failed', { reason })
            lemonToast.error(detail)
        },
    })),
])
