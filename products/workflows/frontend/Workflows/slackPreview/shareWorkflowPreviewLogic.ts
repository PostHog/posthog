import { getShareDisabledReason } from './shareDisabledReason'
import { EmailSendersByIntegrationId, EmailStep, buildWorkflowOutline, listEmailSteps } from './workflowPreviewOutline'

const MAX_IMAGE_BYTES = 1024 * 1024
const MAX_CAPTION_LENGTH = 300
const MAX_OUTLINE_LINE_LENGTH = 500

export interface ShareWorkflowPreviewLogicProps {
    id: string
}

function clip(text: string, maxLength: number): string {
    return text.length > maxLength ? `${text.slice(0, maxLength - 1)}…` : text
}

function decodedSize(base64: string): number {
    return Math.floor((base64.length * 3) / 4)
}

function emailTitle(step: EmailStep): string {
    return step.subject || step.stepName
}

