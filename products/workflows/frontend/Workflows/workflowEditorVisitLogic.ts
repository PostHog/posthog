import { MakeLogicType, connect, events, kea, key, listeners, path, props } from 'kea'
import posthog, { CaptureOptions } from 'posthog-js'

import type { HogFlow, HogFlowActionValidationResult } from './hogflows/types'
import {
    WorkflowBuilderEdit,
    WorkflowStartPath,
    builderProgress,
    classifyEdit,
    workflowStartPath,
} from './workflowBuilderProgress'
import { WorkflowLogicProps, workflowLogic, workflowLogicKey } from './workflowLogic'

interface EditorVisit {
    startPath: WorkflowStartPath
    templateId: string | null
    entrySource: string | null
    openedAt: number
    lastEdit: WorkflowBuilderEdit
    enableAttempted: boolean
}

// Saving a new workflow moves the editor to the saved workflow's URL, which mounts a new logic.
// The visit passes to that logic here, so the move reads as one visit, not a leave and an open.
const visitsMovingToSavedWorkflow = new Map<string, EditorVisit>()

