export const workflowEditorVisitLogic = kea<workflowEditorVisitLogicType>([
    props({} as WorkflowLogicProps),
    key(workflowLogicKey),
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'workflowEditorVisitLogic', key]),
    connect((props: WorkflowLogicProps) => ({
        values: [workflowLogic(props), ['workflow', 'actionValidationErrorsById']],
        actions: [
            workflowLogic(props),
            [
                'setWorkflowValue',
                'setWorkflowValues',
                'workflowCreated',
                'enableBlocked',
                'leaveConfirmed',
                'setScheduleState',
                'setScheduleStartsAtFromPicker',
                'setScheduleTimezone',
                'setScheduleRepeating',
                'addSchedule',
                'deleteSchedule',
            ],
        ],
    })),
    listeners(({ cache, props, values }) => {
        const recordEdit = (visit: EditorVisit, edit: WorkflowBuilderEdit): void => {
            visit.lastEdit = edit
            visit.discardedProgress = null
        }
        const recordFormEdit = (previousState: any): void => {
            const editor = workflowLogic(props)
            const before = editor.selectors.workflow(previousState)
            const edit = classifyEdit(before, editor.values.workflow)
            const visit = cache.visit as EditorVisit | null
            if (!visit || !edit) {
                return
            }
            recordEdit(visit, edit)
            if (edit === 'step_added') {
                visit.lastAddedStepType = addedStepKind(before, editor.values.workflow)
            }
        }
        const recordScheduleEdit = (): void => {
            const visit = cache.visit as EditorVisit | null
            if (visit) {
                recordEdit(visit, 'trigger')
            }
        }
        return {
            setWorkflowValue: (_, __, ___, previousState) => recordFormEdit(previousState),
            setWorkflowValues: (_, __, ___, previousState) => recordFormEdit(previousState),
            setScheduleState: recordScheduleEdit,
            setScheduleStartsAtFromPicker: recordScheduleEdit,
            setScheduleTimezone: recordScheduleEdit,
            setScheduleRepeating: recordScheduleEdit,
            addSchedule: recordScheduleEdit,
            deleteSchedule: recordScheduleEdit,
            enableBlocked: () => {
                const { invalid_step_count, invalid_step_types } = builderProgress(
                    values.workflow,
                    values.actionValidationErrorsById
                )
                // pinned: analytics event name
                posthog.capture('workflow enable blocked', {
                    workflow_id: props.id ?? null,
                    invalid_step_count,
                    invalid_step_types,
                })
            },
            workflowCreated: ({ workflowId }) => {
                cache.createdWorkflowId = workflowId
            },
            leaveConfirmed: () => {
                const visit = cache.visit as EditorVisit | null
                if (visit) {
                    visit.discardedProgress = builderProgress(values.workflow, values.actionValidationErrorsById)
                }
            },
        }
    }),
    events(({ cache, props, values }) => {
        const savedWorkflowId = (): string | null =>
            props.id && props.id !== 'new' ? props.id : ((cache.createdWorkflowId as string | null | undefined) ?? null)

        const visitProperties = (visit: EditorVisit): Record<string, unknown> => ({
            start_path: visit.startPath,
            template_id: visit.templateId,
            entry_source: visit.entrySource,
            workflow_id: savedWorkflowId(),
            status: values.workflow.status,
        })

        const reportLeave = (options?: CaptureOptions): void => {
            const visit = cache.visit as EditorVisit | null
            if (!visit) {
                return
            }
            cache.visit = null
            posthog.capture(
                // pinned: analytics event name
                'workflow editor left',
                {
                    ...visitProperties(visit),
                    ever_saved: savedWorkflowId() !== null,
                    ...(visit.discardedProgress ?? builderProgress(values.workflow, values.actionValidationErrorsById)),
                    last_edit: visit.lastEdit,
                    last_added_step_type: visit.lastAddedStepType,
                },
                options
            )
        }

        const startVisit = (): void => {
            const visit: EditorVisit = {
                startPath: workflowStartPath(props),
                templateId: props.templateId ?? null,
                entrySource: props.entrySource ?? null,
                lastEdit: 'none',
                lastAddedStepType: null,
                discardedProgress: null,
            }
            cache.visit = visit
            // pinned: analytics event name
            posthog.capture('workflow editor opened', visitProperties(visit))
        }

        return {
            afterMount: () => {
                cache.disposables.add(
                    () => {
                        const onPageHide = (): void => reportLeave({ transport: 'sendBeacon' })
                        window.addEventListener('pagehide', onPageHide)
                        return () => window.removeEventListener('pagehide', onPageHide)
                    },
                    'pageLifecycle',
                    { pauseOnPageHidden: KEEP_LISTENING_WHILE_THE_PAGE_HIDES_ON_LEAVE }
                )
                startVisit()
            },
            beforeUnmount: () => reportLeave(),
        }
    }),
])
