import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { LemonDialog } from 'lib/lemon-ui/LemonDialog'
import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { hogFlowsRevisionsList, hogFlowsRevisionsRestoreCreate } from '../generated/api'
import type { HogFlowRevisionBasicApi } from '../generated/api.schemas'
import { workflowLogic } from './workflowLogic'

export interface WorkflowRevisionsLogicProps {
    id: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowRevisionsLogicValues {
    currentTeamIdStrict: number | string // teamLogic
    hasStagedDraft: boolean // workflowLogic
    restoringVersion: number | null
    revisions: HogFlowRevisionBasicApi[]
    revisionsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowRevisionsLogicActions {
    confirmRestoreRevision: (version: number) => { version: number }
    loadRevisions: () => any
    loadRevisionsFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadRevisionsSuccess: (
        revisions: HogFlowRevisionBasicApi[],
        payload?: any
    ) => { revisions: HogFlowRevisionBasicApi[]; payload?: any }
    restoreRevision: (version: number) => { version: number }
    setRestoringVersion: (version: number | null) => { version: number | null }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowRevisionsLogicMeta {
    key: string
}

export type workflowRevisionsLogicType = MakeLogicType<
    workflowRevisionsLogicValues,
    workflowRevisionsLogicActions,
    WorkflowRevisionsLogicProps,
    workflowRevisionsLogicMeta
>

export const workflowRevisionsLogic = kea<workflowRevisionsLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'workflowRevisionsLogic']),
    props({} as WorkflowRevisionsLogicProps),
    key(({ id }) => id),
    connect(({ id }: WorkflowRevisionsLogicProps) => ({
        values: [teamLogic, ['currentTeamIdStrict'], workflowLogic({ id }), ['hasStagedDraft']],
    })),
    actions({
        restoreRevision: (version: number) => ({ version }),
        confirmRestoreRevision: (version: number) => ({ version }),
        setRestoringVersion: (version: number | null) => ({ version }),
    }),
    reducers({
        restoringVersion: [
            null as number | null,
            {
                setRestoringVersion: (_, { version }) => version,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        revisions: [
            [] as HogFlowRevisionBasicApi[],
            {
                loadRevisions: async () => {
                    const response = await hogFlowsRevisionsList(String(values.currentTeamIdStrict), props.id)
                    return response.results
                },
            },
        ],
    })),
    listeners(({ actions, props, values }) => ({
        restoreRevision: ({ version }) => {
            if (values.restoringVersion !== null) {
                return
            }
            LemonDialog.open({
                title: `Restore version ${version} as draft?`,
                description: values.hasStagedDraft
                    ? 'This replaces your current staged draft with this version. The live workflow keeps running until you publish.'
                    : 'This version opens on the canvas as a draft. The live workflow keeps running until you publish.',
                primaryButton: {
                    children: 'Restore as draft',
                    onClick: () => actions.confirmRestoreRevision(version),
                },
                secondaryButton: {
                    children: 'Cancel',
                },
            })
        },
        confirmRestoreRevision: async ({ version }) => {
            actions.setRestoringVersion(version)
            try {
                // overwrite is safe here: the confirm dialog above already warned when a staged
                // draft would be replaced.
                await hogFlowsRevisionsRestoreCreate(String(values.currentTeamIdStrict), props.id, version, {
                    overwrite: true,
                })
                lemonToast.success(`Version ${version} restored as draft`)
                workflowLogic({ id: props.id }).actions.loadWorkflow()
                router.actions.push(urls.workflow(props.id, 'workflow'))
            } catch {
                lemonToast.error('Could not restore this version. Please try again.')
            } finally {
                actions.setRestoringVersion(null)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRevisions()
    }),
])
