export type workflowRevisionsLogicType = MakeLogicType<
    workflowRevisionsLogicValues,
    workflowRevisionsLogicActions,
    WorkflowRevisionsLogicProps,
    workflowRevisionsLogicMeta
>

export const workflowRevisionsLogic = kea<workflowRevisionsLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'workflowRevisionsLogic']),
    props({} as WorkflowRevisionsLogicProps),
    key(({ id }) => id),
    connect(({ id }: WorkflowRevisionsLogicProps) => ({
        values: [teamLogic, ['currentTeamIdStrict'], workflowLogic({ id }), ['hasStagedDraft', 'originalWorkflow']],
    })),
    actions({
        restoreRevision: (version: number) => ({ version }),
        confirmRestoreRevision: (version: number, expectedDraftUpdatedAt: string | null) => ({
            version,
            expectedDraftUpdatedAt,
        }),
        setRestoringVersion: (version: number | null) => ({ version }),
    }),
    reducers({
        restoringVersion: [
            null as number | null,
            {
                setRestoringVersion: (_, { version }) => version,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        revisionsResponse: [
            null as PaginatedHogFlowRevisionBasicListApi | null,
            {
                loadRevisions: async () => {
                    return await hogFlowsRevisionsList(String(values.currentTeamIdStrict), props.id)
                },
            },
        ],
    })),
    selectors({
        revisions: [
            (s) => [s.revisionsResponse],
            (response: PaginatedHogFlowRevisionBasicListApi | null): HogFlowRevisionBasicApi[] =>
                response?.results ?? [],
        ],
        revisionsCount: [
            (s) => [s.revisionsResponse],
            (response: PaginatedHogFlowRevisionBasicListApi | null): number => response?.count ?? 0,
        ],
    }),
    listeners(({ actions, props, values }) => ({
        restoreRevision: ({ version }) => {
            if (values.restoringVersion !== null) {
                return
            }
            // The stamp of the draft this confirmation is about. The restore sends it as a fence, so
            // a draft staged or edited after this dialog opened returns 409 instead of being clobbered.
            const expectedDraftUpdatedAt = values.originalWorkflow?.draft_updated_at ?? null
            LemonDialog.open({
                title: `Restore version ${version} as draft?`,
                description: values.hasStagedDraft
                    ? 'This replaces your current staged draft with this version. The live workflow keeps running until you publish.'
                    : 'This version opens on the canvas as a draft. The live workflow keeps running until you publish.',
                primaryButton: {
                    children: 'Restore as draft',
                    onClick: () => actions.confirmRestoreRevision(version, expectedDraftUpdatedAt),
                },
                secondaryButton: {
                    children: 'Cancel',
                },
            })
        },
        confirmRestoreRevision: async ({ version, expectedDraftUpdatedAt }) => {
            if (values.restoringVersion !== null) {
                return
            }
            actions.setRestoringVersion(version)
            try {
                // overwrite only replaces the draft the confirm dialog warned about: the expected
                // stamp fences the write, so a draft that changed since returns 409 below.
                await hogFlowsRevisionsRestoreCreate(String(values.currentTeamIdStrict), props.id, version, {
                    overwrite: true,
                    expected_draft_updated_at: expectedDraftUpdatedAt,
                })
                lemonToast.success(`Version ${version} restored as draft`)
                workflowLogic({ id: props.id }).actions.loadWorkflow()
                router.actions.push(urls.workflow(props.id, 'workflow'))
            } catch (error) {
                if (error instanceof ApiError && error.status === 409) {
                    lemonToast.error('The staged draft changed while you were confirming. Review it and try again.')
                    workflowLogic({ id: props.id }).actions.loadWorkflow()
                } else {
                    lemonToast.error('Could not restore this version. Please try again.')
                }
            } finally {
                actions.setRestoringVersion(null)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRevisions()
    }),
])
