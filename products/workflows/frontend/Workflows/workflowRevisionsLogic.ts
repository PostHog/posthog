import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'

import { ApiError } from 'lib/api'
import { LemonDialog } from 'lib/lemon-ui/LemonDialog'
import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { hogFlowsRevisionsList, hogFlowsRevisionsRestoreCreate } from '../generated/api'
import type { HogFlowRevisionBasicApi, PaginatedHogFlowRevisionBasicListApi } from '../generated/api.schemas'
import type { HogFlow } from './hogflows/types'
import { workflowLogic } from './workflowLogic'

export interface WorkflowRevisionsLogicProps {
    id: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowRevisionsLogicValues {
    currentTeamIdStrict: number | string // teamLogic
    hasStagedDraft: boolean // workflowLogic
    originalWorkflow: HogFlow | null // workflowLogic
    restoringVersion: number | null
    revisions: HogFlowRevisionBasicApi[]
    revisionsCount: number
    revisionsResponse: PaginatedHogFlowRevisionBasicListApi | null
    revisionsResponseLoading: boolean
}

