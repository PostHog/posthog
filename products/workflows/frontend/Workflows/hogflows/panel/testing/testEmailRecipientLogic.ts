export const testEmailRecipientLogic = kea<testEmailRecipientLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'hogflows', 'panel', 'testing', 'testEmailRecipientLogic']),
    connect(() => ({
        values: [userLogic, ['user']],
    })),
    actions({
        setEmailAddressOverride: (email: string) => ({ email }),
        storeEmailAddressOverride: (override: StoredEmailAddressOverride | null) => ({ override }),
    }),
    reducers({
        storedEmailAddressOverride: [
            null as StoredEmailAddressOverride | null,
            { persist: true },
            {
                storeEmailAddressOverride: (_, { override }) => override,
            },
        ],
    }),
    selectors({
        // The browser keeps the address across sessions, so it only applies to the person who typed it.
        emailAddressOverride: [
            (s) => [s.storedEmailAddressOverride, s.user],
            (stored: StoredEmailAddressOverride | null, user: UserType | null): string | null =>
                stored && stored.userUuid === user?.uuid ? stored.email : null,
        ],
        testEmailAddress: [
            (s) => [s.emailAddressOverride, s.user],
            (emailAddressOverride: string | null, user: UserType | null): string =>
                emailAddressOverride ?? user?.email ?? '',
        ],
    }),
    listeners(({ actions, values }) => ({
        setEmailAddressOverride: ({ email }) => {
            actions.storeEmailAddressOverride(email && values.user ? { email, userUuid: values.user.uuid } : null)
        },
    })),
])
