import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { userLogic } from 'scenes/userLogic'

import { UserType } from '~/types'

import { isEmailAction } from '../../steps/types'
import { HogFlow } from '../../types'

interface StoredEmailAddressOverride {
    email: string
    userUuid: string
}

// One visible recipient and no cc/bcc is what keeps a real test send away from the workflow's audience.
export const withTestEmailRecipient = (workflow: HogFlow, recipientEmail: string): HogFlow => ({
    ...workflow,
    actions: workflow.actions.map((action) => {
        if (!isEmailAction(action)) {
            return action
        }
        const email = action.config.inputs?.email
        return {
            ...action,
            config: {
                ...action.config,
                inputs: {
                    ...action.config.inputs,
                    email: {
                        ...email,
                        value: { ...email?.value, to: { email: recipientEmail, name: '' }, cc: '', bcc: '' },
                    },
                },
            },
        }
    }),
})

