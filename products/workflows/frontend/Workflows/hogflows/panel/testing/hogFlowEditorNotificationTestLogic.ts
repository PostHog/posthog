const STANDARD_SEARCH_RANGE = `-7d`

function emailDisabledReason(email: string | null): string | null {
    return isEmail(email ?? '') ? null : 'Must enter a valid email address'
}

function sandboxRecipientDisabledReason(
    sandboxTestMembers: OrganizationMemberType[],
    members: OrganizationMemberType[] | null,
    membersLoading: boolean,
    membersLoadFailed: boolean,
    testRecipient: string | null
): string | null {
    if (membersLoadFailed && !membersLoading) {
        return "Couldn't load your organization's members. Refresh the page to try again."
    }
    if (membersLoading || members === null) {
        return 'Loading verified members'
    }
    if (sandboxTestMembers.length === 0) {
        return 'No one in your organization has verified their email address yet. Verify yours to send a sandbox test.'
    }
    return testRecipient ? emailDisabledReason(testRecipient) : 'Choose a verified member of your organization'
}

function withRecipientEmail(globals: Record<string, any>, recipient: string | null): Record<string, any> {
    if (!recipient || !globals.person) {
        return globals
    }
    return {
        ...globals,
        person: { ...globals.person, properties: { ...globals.person.properties, email: recipient } },
    }
}

