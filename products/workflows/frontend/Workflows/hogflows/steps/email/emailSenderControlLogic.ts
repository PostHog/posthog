export const emailSenderControlLogic = kea<emailSenderControlLogicType>([
    path((key) => [
        'products',
        'workflows',
        'frontend',
        'Workflows',
        'hogflows',
        'steps',
        'email',
        'emailSenderControlLogic',
        key,
    ]),
    props({} as EmailSenderControlLogicProps),
    key(
        ({ workflowLogicProps, actionId }: EmailSenderControlLogicProps) =>
            `${workflowLogicProps.id || 'new'}:${actionId}`
    ),
    connect(({ workflowLogicProps }: EmailSenderControlLogicProps) => ({
        values: [
            workflowLogic(workflowLogicProps),
            ['workflow', 'isViewOnly'],
            sandboxSenderLogic,
            ['canAdoptSandbox', 'sandboxStatus'],
            integrationsLogic,
            ['integrations'],
            teamLogic,
            ['currentTeam'],
        ],
        actions: [
            workflowLogic(workflowLogicProps),
            ['setWorkflowAction'],
            sandboxSenderLogic,
            ['provisionSandboxSender', 'loadSandboxStatusSuccess'],
            integrationsLogic,
            ['loadIntegrationsSuccess'],
            teamLogic,
            ['refreshCurrentTeam', 'refreshCurrentTeamSuccess'],
        ],
    })),
    actions({
        chooseSender: (choice: SenderChoice) => ({ choice }),
        setPendingSwitch: (pendingSwitch: PendingSwitch) => ({ pendingSwitch }),
        confirmSwitch: true,
        cancelSwitch: true,
        switchToSandbox: true,
        preselectDefaultSender: true,
    }),
    reducers({
        pendingSwitch: [
            null as PendingSwitch | null,
            {
                setPendingSwitch: (_, { pendingSwitch }) => pendingSwitch,
                confirmSwitch: () => null,
                cancelSwitch: () => null,
            },
        ],
    }),
    selectors({
        action: [
            (s, p) => [s.workflow, p.actionId],
            (workflow: HogFlow, actionId: string): EmailStepAction | null => {
                const action = workflow.actions.find((candidate) => candidate.id === actionId)
                return isEmailStep(action) ? action : null
            },
        ],
        hasVerifiedSender: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): boolean | null => hasOwnSender(integrations),
        ],
        testSenderOnly: [
            (s) => [s.canAdoptSandbox, s.hasVerifiedSender],
            (canAdoptSandbox: boolean, hasVerifiedSender: boolean | null): boolean =>
                canAdoptSandbox && hasVerifiedSender === false,
        ],
        awaitsVerifiedSender: [
            (s) => [s.action, s.testSenderOnly],
            (action: EmailStepAction | null, testSenderOnly: boolean): boolean =>
                testSenderOnly && action?.type === 'email_sandbox',
        ],
        projectDefaultSenderId: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | TeamPublicType | null): number | null =>
                (currentTeam && 'workflows_config' in currentTeam
                    ? currentTeam.workflows_config?.default_email_integration_id
                    : null) ?? null,
        ],
        defaultSender: [
            (s) => [s.canAdoptSandbox, s.integrations, s.projectDefaultSenderId],
            (
                canAdoptSandbox: boolean,
                integrations: IntegrationType[] | null,
                projectDefaultSenderId: number | null
            ): DefaultEmailSender | null =>
                canAdoptSandbox ? resolveDefaultEmailSender(integrations, projectDefaultSenderId) : null,
        ],
        senderToPreselect: [
            (s) => [s.action, s.defaultSender, s.projectDefaultSenderId, s.integrations, s.isViewOnly],
            (
                action: EmailStepAction | null,
                defaultSender: DefaultEmailSender | null,
                projectDefaultSenderId: number | null,
                integrations: IntegrationType[] | null,
                isViewOnly: boolean
            ): number | null => {
                if (action?.type !== 'email_sandbox' || !defaultSender || isViewOnly) {
                    return null
                }
                const projectDefaultHidden =
                    defaultSender.reason !== 'project_default' && projectDefaultSenderId !== null
                const sender = integrations?.find((integration) => integration.id === defaultSender.integrationId)
                return sender && !projectDefaultHidden && !isSendingStopped(sender) ? sender.id : null
            },
        ],
        showSandboxOption: [
            (s, p) => [s.action, s.canAdoptSandbox, s.hasVerifiedSender, s.workflow, p.workflowLogicProps],
            (
                action: EmailStepAction | null,
                canAdoptSandbox: boolean,
                hasVerifiedSender: boolean | null,
                workflow: HogFlow,
                workflowLogicProps: WorkflowLogicProps
            ): boolean =>
                (canAdoptSandbox &&
                    hasVerifiedSender !== true &&
                    sandboxSenderAllowed(workflow, !!workflowLogicProps.editTemplateId) &&
                    !!action &&
                    sandboxTakesStepId(action)) ||
                action?.type === 'email_sandbox',
        ],
    }),
    subscriptions(({ actions, values, cache }) => ({
        showSandboxOption: (shown: boolean) => {
            if (shown && !cache.offerReported) {
                cache.offerReported = true
                // pinned: analytics event name and properties, renaming breaks dashboards
                posthog.capture('workflows sandbox sender offered', { step_type: values.action?.type ?? null })
            }
        },
        awaitsVerifiedSender: (awaits: boolean, previous: boolean | undefined) => {
            if (awaits && !previous) {
                integrationsLogic.actions.startPolling()
            } else if (!awaits && previous) {
                integrationsLogic.actions.stopPolling()
                actions.refreshCurrentTeam()
            }
        },
    })),
    listeners(({ actions, values, props }) => {
        function replaceStep(next: EmailStepAction, previous: EmailStepAction, preselected = false): void {
            actions.setWorkflowAction(props.actionId, next)
            if (kindOf(next) !== kindOf(previous)) {
                // pinned: analytics event name and properties, renaming breaks dashboards
                posthog.capture('workflows email sender changed', {
                    from_kind: kindOf(previous),
                    to_kind: kindOf(next),
                    preselected,
                })
            }
        }

        async function preselectDefaultSender(): Promise<void> {
            if (values.senderToPreselect === null) {
                return
            }
            if (!(await saveOpenCanvasEdit())) {
                return
            }
            const action = values.action
            const senderId = values.senderToPreselect
            if (action?.type === 'email_sandbox' && senderId !== null) {
                replaceStep(toOwnEmailAction(action, senderId), action, true)
            }
        }

        return {
            preselectDefaultSender,
            loadIntegrationsSuccess: preselectDefaultSender,
            loadSandboxStatusSuccess: preselectDefaultSender,
            refreshCurrentTeamSuccess: preselectDefaultSender,
            chooseSender: ({ choice }) => {
                const action = values.action
                if (!action) {
                    return
                }
                if (choice === 'sandbox') {
                    if (action.type === 'email_sandbox') {
                        return
                    }
                    const droppedSettings = ownOnlySettings(action)
                    if (droppedSettings.length > 0) {
                        actions.setPendingSwitch({ droppedSettings })
                    } else {
                        actions.switchToSandbox()
                    }
                    return
                }
                if (action.type === 'email_sandbox') {
                    replaceStep(toOwnEmailAction(action, choice), action)
                }
            },
            confirmSwitch: () => {
                actions.switchToSandbox()
            },
            switchToSandbox: () => {
                const action = values.action
                if (action?.type !== 'function_email') {
                    return
                }
                replaceStep(toSandboxAction(action), action)
                if (values.sandboxStatus?.integration_id === null) {
                    actions.provisionSandboxSender('sender_control')
                }
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.preselectDefaultSender()
    }),
    beforeUnmount(({ values }) => {
        if (values.awaitsVerifiedSender) {
            integrationsLogic.actions.stopPolling()
        }
    }),
])
