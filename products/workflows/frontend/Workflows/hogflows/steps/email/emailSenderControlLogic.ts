export type emailSenderControlLogicType = MakeLogicType<
    emailSenderControlLogicValues,
    emailSenderControlLogicActions,
    EmailSenderControlLogicProps,
    emailSenderControlLogicMeta
>

export const emailSenderControlLogic = kea<emailSenderControlLogicType>([
    path((key) => [
        'products',
        'workflows',
        'frontend',
        'Workflows',
        'hogflows',
        'steps',
        'email',
        'emailSenderControlLogic',
        key,
    ]),
    props({} as EmailSenderControlLogicProps),
    key(
        ({ workflowLogicProps, actionId }: EmailSenderControlLogicProps) =>
            `${workflowLogicProps.id || 'new'}:${actionId}`
    ),
    connect(({ workflowLogicProps }: EmailSenderControlLogicProps) => ({
        values: [
            workflowLogic(workflowLogicProps),
            ['workflow'],
            sandboxSenderLogic,
            ['canAdoptSandbox', 'sandboxStatus'],
        ],
        actions: [
            workflowLogic(workflowLogicProps),
            ['setWorkflowAction'],
            sandboxSenderLogic,
            ['provisionSandboxSender'],
        ],
    })),
    actions({
        chooseSender: (choice: SenderChoice) => ({ choice }),
        setPendingSwitch: (pendingSwitch: PendingSwitch) => ({ pendingSwitch }),
        confirmSwitch: true,
        cancelSwitch: true,
        switchToSandbox: true,
    }),
    reducers({
        pendingSwitch: [
            null as PendingSwitch | null,
            {
                setPendingSwitch: (_, { pendingSwitch }) => pendingSwitch,
                confirmSwitch: () => null,
                cancelSwitch: () => null,
            },
        ],
    }),
    selectors({
        action: [
            (s, p) => [s.workflow, p.actionId],
            (workflow: HogFlow, actionId: string): EmailStepAction | null => {
                const action = workflow.actions.find((candidate) => candidate.id === actionId)
                return isEmailStep(action) ? action : null
            },
        ],
        showSandboxOption: [
            (s, p) => [s.action, s.canAdoptSandbox, s.workflow, p.workflowLogicProps],
            (
                action: EmailStepAction | null,
                canAdoptSandbox: boolean,
                workflow: HogFlow,
                workflowLogicProps: WorkflowLogicProps
            ): boolean =>
                (canAdoptSandbox &&
                    sandboxSenderAllowed(workflow, !!workflowLogicProps.editTemplateId) &&
                    !!action &&
                    sandboxTakesStepId(action)) ||
                action?.type === 'email_sandbox',
        ],
    }),
    listeners(({ actions, values, props }) => {
        function replaceStep(next: EmailStepAction, previous: EmailStepAction): void {
            actions.setWorkflowAction(props.actionId, next)
            if (kindOf(next) !== kindOf(previous)) {
                // pinned: analytics event name and properties, renaming breaks dashboards
                posthog.capture('workflows email sender changed', {
                    from_kind: kindOf(previous),
                    to_kind: kindOf(next),
                })
            }
        }

        return {
            chooseSender: ({ choice }) => {
                const action = values.action
                if (!action) {
                    return
                }
                if (choice === 'sandbox') {
                    if (action.type === 'email_sandbox') {
                        return
                    }
                    const droppedSettings = ownOnlySettings(action)
                    if (droppedSettings.length > 0) {
                        actions.setPendingSwitch({ droppedSettings })
                    } else {
                        actions.switchToSandbox()
                    }
                    return
                }
                if (action.type === 'email_sandbox') {
                    replaceStep(toOwnEmailAction(action, choice), action)
                }
            },
            confirmSwitch: () => {
                actions.switchToSandbox()
            },
            switchToSandbox: () => {
                const action = values.action
                if (action?.type !== 'function_email') {
                    return
                }
                replaceStep(toSandboxAction(action), action)
                if (values.sandboxStatus?.integration_id === null) {
                    actions.provisionSandboxSender('sender_control')
                }
            },
        }
    }),
])
