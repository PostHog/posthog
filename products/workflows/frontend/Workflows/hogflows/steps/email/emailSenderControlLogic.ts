import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { sandboxSenderLogic } from '../../../../Channels/sandboxSenderLogic'
import type { WorkflowEmailSandboxStatusApi } from '../../../../generated/api.schemas'
import { WorkflowLogicProps, workflowLogic } from '../../../workflowLogic'
import type { HogFlow } from '../../types'
import {
    EmailStepAction,
    OwnOnlySetting,
    isEmailStep,
    ownOnlySettings,
    sandboxSenderAllowed,
    sandboxTakesStepId,
    toOwnEmailAction,
    toSandboxAction,
} from './emailStepVariants'

export interface EmailSenderControlLogicProps {
    workflowLogicProps: WorkflowLogicProps
    actionId: string
}

export type SenderChoice = number | 'sandbox'

export interface PendingSwitch {
    droppedSettings: OwnOnlySetting[]
}

type SenderKind = 'own' | 'sandbox'

function kindOf(action: EmailStepAction): SenderKind {
    return action.type === 'email_sandbox' ? 'sandbox' : 'own'
}

