export interface emailSenderControlLogicValues {
    canAdoptSandbox: boolean // sandboxSenderLogic
    sandboxStatus: WorkflowEmailSandboxStatusApi | null // sandboxSenderLogic
    workflow: HogFlow // workflowLogic
    action: EmailStepAction | null
    pendingSwitch: PendingSwitch | null
    showSandboxOption: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface emailSenderControlLogicActions {
    provisionSandboxSender: (surface: import('../../../../Channels/sandboxSender').SandboxSenderSurface) => {
        surface: import('../../../../Channels/sandboxSender').SandboxSenderSurface
    } // sandboxSenderLogic
    setWorkflowAction: (
        actionId: string,
        action: import('../../types').HogFlowAction
    ) => {
        action: import('../../types').HogFlowAction
        actionId: string
    } // workflowLogic
    cancelSwitch: () => {
        value: true
    }
    chooseSender: (choice: SenderChoice) => {
        choice: SenderChoice
    }
    confirmSwitch: () => {
        value: true
    }
    setPendingSwitch: (pendingSwitch: PendingSwitch) => {
        pendingSwitch: PendingSwitch
    }
    switchToSandbox: () => {
        value: true
    }
}

