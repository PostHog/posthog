export const stepAiDecisionLogic = kea<stepAiDecisionLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'hogflows', 'steps', 'stepAiDecisionLogic', key]),
    props({} as StepAiDecisionLogicProps),
    key(({ workflowLogicProps, actionId }: StepAiDecisionLogicProps) => `${workflowLogicProps.id || 'new'}-${actionId}`),
    connect(({ workflowLogicProps }: StepAiDecisionLogicProps) => ({
        values: [
            workflowLogic(workflowLogicProps),
            ['workflow', 'workflowSanitized', 'edgesByActionId'],
            hogFlowEditorTestLogic(workflowLogicProps),
            ['sampleGlobals', 'accumulatedVariables', 'workflowVariableDefaults'],
        ],
        actions: [workflowLogic(workflowLogicProps), ['setWorkflowAction', 'setWorkflowActionEdges']],
    })),
    actions({
        updateConfig: (patch: Partial<AiDecisionConfig>) => ({ patch }),
        setOption: (index: number, patch: Partial<AiDecisionOption>) => ({ index, patch }),
        addOption: true,
        removeOption: (index: number) => ({ index }),
        setAnswerType: (answerType: AiDecisionAnswerType) => ({ answerType }),
        setUnsureEnabled: (enabled: boolean) => ({ enabled }),
    }),
    loaders(({ values, props }) => {
        const runTestInvocation = async (mockAsyncFunctions: boolean): Promise<HogflowTestResult> => {
            const { workflow } = values
            const globals = values.sampleGlobals ?? createExampleEvent(workflow.team_id, workflow.name)
            return await api.hogFlows.createTestInvocation(workflow.id, {
                configuration: values.workflowSanitized,
                globals: {
                    ...globals,
                    variables: { ...values.workflowVariableDefaults, ...values.accumulatedVariables },
                },
                mock_async_functions: mockAsyncFunctions,
                current_action_id: props.actionId,
            })
        }

        return {
            personTestOutcome: [
                null as AiDecisionTestOutcome | null,
                {
                    runPersonTest: async (): Promise<AiDecisionTestOutcome | null> => {
                        if (!values.config) {
                            return null
                        }
                        try {
                            return readAiDecisionTestOutcome(values.config, await runTestInvocation(false))
                        } catch (error) {
                            return { status: 'failed', message: getTestRunErrorMessage(error) }
                        }
                    },
                },
            ],
            contextPreview: [
                null as AiDecisionContextPreview | null,
                {
                    loadContextPreview: async (): Promise<AiDecisionContextPreview> => {
                        try {
                            return readAiDecisionContextPreview(await runTestInvocation(true))
                        } catch (error) {
                            return { status: 'failed', message: getTestRunErrorMessage(error) }
                        }
                    },
                },
            ],
        }
    }),
    selectors({
        action: [
            (s, p) => [s.workflow, p.actionId],
            (workflow: HogFlow, actionId: string): AiDecisionAction | null => {
                const action = workflow.actions.find((a) => a.id === actionId)
                return action?.type === 'ai_decision' ? (action as AiDecisionAction) : null
            },
        ],
        config: [(s) => [s.action], (action: AiDecisionAction | null): AiDecisionConfig | null => action?.config ?? null],
        actionEdges: [
            (s, p) => [s.edgesByActionId, p.actionId],
            (edgesByActionId: Record<string, HogFlowEdge[]>, actionId: string): HogFlowEdge[] =>
                edgesByActionId[actionId] ?? [],
        ],
        removeOptionDisabledReasons: [
            (s, p) => [s.config, s.actionEdges, s.edgesByActionId, p.actionId],
            (
                config: AiDecisionConfig | null,
                actionEdges: HogFlowEdge[],
                edgesByActionId: Record<string, HogFlowEdge[]>,
                actionId: string
            ): (string | undefined)[] => {
                if (!config) {
                    return []
                }
                const options = getAiDecisionOptions(config)
                if (options.length <= MIN_AI_DECISION_OPTIONS) {
                    return options.map(() => `A question needs at least ${MIN_AI_DECISION_OPTIONS} options`)
                }
                return options.map((_, index) => {
                    const next = withAiDecisionOptionRemoved(config, index)
                    const { droppedEdges } = planAiDecisionBranchEdges(actionId, actionEdges, config, next, index)
                    return getBranchesRemovalDisabledReason(droppedEdges, edgesByActionId)
                })
            },
        ],
        answerTypeDisabledReason: [
            (s, p) => [s.config, s.actionEdges, s.edgesByActionId, p.actionId],
            (
                config: AiDecisionConfig | null,
                actionEdges: HogFlowEdge[],
                edgesByActionId: Record<string, HogFlowEdge[]>,
                actionId: string
            ): string | undefined => {
                if (!config) {
                    return undefined
                }
                const next = withAiDecisionAnswerType(config, otherAnswerType(config.answer_type))
                const { droppedEdges } = planAiDecisionBranchEdges(actionId, actionEdges, config, next)
                return getBranchesRemovalDisabledReason(droppedEdges, edgesByActionId)
            },
        ],
        unsureOffDisabledReason: [
            (s, p) => [s.config, s.actionEdges, s.edgesByActionId, p.actionId],
            (
                config: AiDecisionConfig | null,
                actionEdges: HogFlowEdge[],
                edgesByActionId: Record<string, HogFlowEdge[]>,
                actionId: string
            ): string | undefined => {
                if (!config?.unsure_enabled) {
                    return undefined
                }
                const next = { ...config, unsure_enabled: false }
                const { droppedEdges } = planAiDecisionBranchEdges(actionId, actionEdges, config, next)
                return getBranchesRemovalDisabledReason(droppedEdges, edgesByActionId)
            },
        ],
    }),
    listeners(({ actions, values, props }) => {
        const applyConfig = (next: AiDecisionConfig, removedAnswerIndex?: number): void => {
            const action = values.action
            if (!action) {
                return
            }
            const { branchEdges, droppedEdges } = planAiDecisionBranchEdges(
                props.actionId,
                values.actionEdges,
                action.config,
                next,
                removedAnswerIndex
            )
            if (getBranchesRemovalDisabledReason(droppedEdges, values.edgesByActionId)) {
                return
            }
            actions.setWorkflowAction(props.actionId, { ...action, config: next })

            const isOwnBranchEdge = (edge: HogFlowEdge): boolean => edge.from === props.actionId && edge.type === 'branch'
            const currentBranchEdgeCount = values.actionEdges.filter(isOwnBranchEdge).length
            if (droppedEdges.length > 0 || branchEdges.length !== currentBranchEdgeCount) {
                const otherEdges = values.actionEdges.filter((edge) => !isOwnBranchEdge(edge))
                actions.setWorkflowActionEdges(props.actionId, [...branchEdges, ...otherEdges])
            }
        }

        return {
            updateConfig: ({ patch }) => {
                if (values.config) {
                    applyConfig({ ...values.config, ...patch })
                }
            },
            setOption: ({ index, patch }) => {
                if (values.config) {
                    const options = getAiDecisionOptions(values.config).map((option, i) =>
                        i === index ? { ...option, ...patch } : option
                    )
                    applyConfig({ ...values.config, options })
                }
            },
            addOption: () => {
                if (values.config) {
                    applyConfig(withAiDecisionOptionAdded(values.config))
                }
            },
            removeOption: ({ index }) => {
                if (values.config && getAiDecisionOptions(values.config).length > MIN_AI_DECISION_OPTIONS) {
                    applyConfig(withAiDecisionOptionRemoved(values.config, index), index)
                }
            },
            setAnswerType: ({ answerType }) => {
                if (values.config) {
                    applyConfig(withAiDecisionAnswerType(values.config, answerType))
                }
            },
            setUnsureEnabled: ({ enabled }) => {
                if (values.config) {
                    applyConfig({ ...values.config, unsure_enabled: enabled })
                }
            },
        }
    }),
])
