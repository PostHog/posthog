import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiError } from 'lib/api-error'
import { teamLogic } from 'scenes/teamLogic'

import {
    workflowT3CodeMachinesRetrieve,
    workflowT3CodeProjectsCreate,
    workflowT3CodeWebhookTasksCreate,
} from '../../../../generated/api'
import type {
    T3CodeMachineApi,
    T3CodeProjectApi,
    T3CodeProjectsApi,
    T3CodeWebhookTaskApi,
} from '../../../../generated/api.schemas'

export interface T3CodeTaskSetupLogicProps {
    actionId: string
    onWebhookUrl: (webhookUrl: string) => void
}

export type T3CodeCallKind = 'projects' | 'task'

export interface T3CodePendingApproval {
    kind: T3CodeCallKind
    approvalToken: string
}

interface CreateTaskPayload {
    title: string
    approvalToken?: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface t3CodeTaskSetupLogicValues {
    currentTeamId: number | null
    machines: T3CodeMachineApi[] | null
    machinesLoading: boolean
    projectsResult: T3CodeProjectsApi | null
    projectsResultLoading: boolean
    taskResult: T3CodeWebhookTaskApi | null
    taskResultLoading: boolean
    machine: string | null
    project: string | null
    taskTitle: string | null
    error: string | null
    projects: T3CodeProjectApi[] | null
    pendingApproval: T3CodePendingApproval | null
    createdWebhookUrl: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface t3CodeTaskSetupLogicActions {
    setMachine: (machine: string | null) => { machine: string | null }
    setProject: (project: string | null) => { project: string | null }
    allowPendingCall: () => { value: true }
    loadMachines: () => void
    loadMachinesSuccess: (
        machines: T3CodeMachineApi[] | null,
        payload?: any
    ) => { machines: T3CodeMachineApi[] | null; payload?: any }
    loadMachinesFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    loadProjects: (approvalToken?: string) => string | undefined
    loadProjectsSuccess: (
        projectsResult: T3CodeProjectsApi | null,
        payload?: string
    ) => { projectsResult: T3CodeProjectsApi | null; payload?: string }
    loadProjectsFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    createTask: (payload: CreateTaskPayload) => CreateTaskPayload
    createTaskSuccess: (
        taskResult: T3CodeWebhookTaskApi | null,
        payload?: CreateTaskPayload
    ) => { taskResult: T3CodeWebhookTaskApi | null; payload?: CreateTaskPayload }
    createTaskFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
}

export type t3CodeTaskSetupLogicType = MakeLogicType<
    t3CodeTaskSetupLogicValues,
    t3CodeTaskSetupLogicActions,
    T3CodeTaskSetupLogicProps
>

function errorDetail(errorObject: unknown, fallback: string): string {
    return errorObject instanceof ApiError && errorObject.detail ? errorObject.detail : fallback
}

export const t3CodeTaskSetupLogic = kea<t3CodeTaskSetupLogicType>([
    props({} as T3CodeTaskSetupLogicProps),
    key((props) => props.actionId),
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'hogflows', 't3CodeTaskSetupLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        setMachine: (machine: string | null) => ({ machine }),
        setProject: (project: string | null) => ({ project }),
        allowPendingCall: true,
    }),
    loaders(({ values }) => ({
        machines: [
            null as T3CodeMachineApi[] | null,
            {
                loadMachines: async () => (await workflowT3CodeMachinesRetrieve(String(values.currentTeamId))).machines,
            },
        ],
        projectsResult: [
            null as T3CodeProjectsApi | null,
            {
                loadProjects: async (approvalToken?: string) =>
                    values.machine
                        ? await workflowT3CodeProjectsCreate(String(values.currentTeamId), {
                              machine: values.machine,
                              approval_token: approvalToken,
                          })
                        : null,
            },
        ],
        taskResult: [
            null as T3CodeWebhookTaskApi | null,
            {
                createTask: async ({ title, approvalToken }: CreateTaskPayload) =>
                    values.machine && values.project
                        ? await workflowT3CodeWebhookTasksCreate(String(values.currentTeamId), {
                              machine: values.machine,
                              project_id: values.project,
                              title,
                              approval_token: approvalToken,
                          })
                        : null,
            },
        ],
    })),
    reducers({
        machine: [null as string | null, { setMachine: (_, { machine }) => machine }],
        project: [
            null as string | null,
            {
                setProject: (_, { project }) => project,
                setMachine: () => null,
            },
        ],
        taskTitle: [null as string | null, { createTask: (_, { title }) => title }],
        projectsResult: { setMachine: () => null, loadProjectsFailure: () => null },
        taskResult: { setMachine: () => null, setProject: () => null, createTaskFailure: () => null },
        error: [
            null as string | null,
            {
                setMachine: () => null,
                setProject: () => null,
                loadProjects: () => null,
                createTask: () => null,
                loadMachinesFailure: (_, { errorObject }) =>
                    errorDetail(errorObject, "PostHog couldn't load your T3 Code connections. Try again."),
                loadProjectsFailure: (_, { errorObject }) =>
                    errorDetail(errorObject, "PostHog couldn't load the projects on this machine. Try again."),
                createTaskFailure: (_, { errorObject }) =>
                    errorDetail(errorObject, "PostHog couldn't create the task in T3 Code. Try again."),
            },
        ],
    }),
    selectors({
        projects: [
            (s) => [s.projectsResult],
            (projectsResult): T3CodeProjectApi[] | null =>
                projectsResult?.status === 'ok' ? (projectsResult.projects ?? []) : null,
        ],
        pendingApproval: [
            (s) => [s.projectsResult, s.taskResult],
            (projectsResult, taskResult): T3CodePendingApproval | null => {
                if (taskResult?.status === 'needs_approval' && taskResult.approval_token) {
                    return { kind: 'task', approvalToken: taskResult.approval_token }
                }
                if (projectsResult?.status === 'needs_approval' && projectsResult.approval_token) {
                    return { kind: 'projects', approvalToken: projectsResult.approval_token }
                }
                return null
            },
        ],
        createdWebhookUrl: [
            (s) => [s.taskResult],
            (taskResult): string | null => (taskResult?.status === 'ok' ? (taskResult.webhook_url ?? null) : null),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        setMachine: ({ machine }) => {
            if (machine) {
                actions.loadProjects()
            }
        },
        allowPendingCall: () => {
            const pending = values.pendingApproval
            if (pending?.kind === 'projects') {
                actions.loadProjects(pending.approvalToken)
            } else if (pending?.kind === 'task' && values.taskTitle) {
                actions.createTask({ title: values.taskTitle, approvalToken: pending.approvalToken })
            }
        },
        createTaskSuccess: ({ taskResult }) => {
            if (taskResult?.status === 'ok' && taskResult.webhook_url) {
                props.onWebhookUrl(taskResult.webhook_url)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadMachines()
    }),
])
