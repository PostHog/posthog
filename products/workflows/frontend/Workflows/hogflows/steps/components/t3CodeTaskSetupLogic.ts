async function replyForSelection<T>(
    request: Promise<T>,
    breakpoint: BreakPointFunction,
    isStillSelected: () => boolean
): Promise<T | null> {
    try {
        const reply = await request
        breakpoint()
        return isStillSelected() ? reply : null
    } catch (error) {
        breakpoint()
        if (isStillSelected()) {
            throw error
        }
        return null
    }
}

function errorDetail(errorObject: unknown, fallback: string): string {
    return errorObject instanceof ApiError && errorObject.detail ? errorObject.detail : fallback
}

export const t3CodeTaskSetupLogic = kea<t3CodeTaskSetupLogicType>([
    props({} as T3CodeTaskSetupLogicProps),
    key((props) => props.actionId),
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'hogflows', 't3CodeTaskSetupLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        setMachine: (machine: string | null) => ({ machine }),
        setProject: (project: string | null) => ({ project }),
        allowPendingCall: true,
    }),
    loaders(({ values }) => ({
        machines: [
            null as T3CodeMachineApi[] | null,
            {
                loadMachines: async () => (await workflowT3CodeMachinesRetrieve(String(values.currentTeamId))).machines,
            },
        ],
        projectsResult: [
            null as T3CodeProjectsApi | null,
            {
                loadProjects: async (approvalToken: string | undefined, breakpoint) => {
                    const { machine } = values
                    if (!machine) {
                        return null
                    }
                    return await replyForSelection(
                        workflowT3CodeProjectsCreate(String(values.currentTeamId), {
                            machine,
                            approval_token: approvalToken,
                        }),
                        breakpoint,
                        () => values.machine === machine
                    )
                },
            },
        ],
        moreProjectsResult: [
            null as T3CodeProjectsApi | null,
            {
                loadMoreProjects: async (approvalToken: string | undefined, breakpoint) => {
                    const { machine, nextCursor, projectListId } = values
                    if (!machine || nextCursor === null) {
                        return null
                    }
                    return await replyForSelection(
                        workflowT3CodeProjectsCreate(String(values.currentTeamId), {
                            machine,
                            cursor: nextCursor,
                            approval_token: approvalToken,
                        }),
                        breakpoint,
                        () => values.projectListId === projectListId && values.nextCursor === nextCursor
                    )
                },
            },
        ],
        taskResult: [
            null as T3CodeWebhookTaskApi | null,
            {
                createTask: async ({ title, approvalToken }: CreateTaskPayload, breakpoint) => {
                    const { machine, project } = values
                    if (!machine || !project) {
                        return null
                    }
                    return await replyForSelection(
                        workflowT3CodeWebhookTasksCreate(String(values.currentTeamId), {
                            machine,
                            project_id: project,
                            title,
                            approval_token: approvalToken,
                        }),
                        breakpoint,
                        () => values.machine === machine && values.project === project
                    )
                },
            },
        ],
    })),
    reducers({
        machine: [null as string | null, { setMachine: (_, { machine }) => machine }],
        project: [
            null as string | null,
            {
                setProject: (_, { project }) => project,
                setMachine: () => null,
            },
        ],
        taskTitle: [null as string | null, { createTask: (_, { title }) => title }],
        projectsResult: { setMachine: () => null, loadProjectsFailure: () => null },
        moreProjectsResult: { setMachine: () => null, loadProjects: () => null, loadMoreProjectsFailure: () => null },
        // Pages after the first, appended as the member loads them.
        laterProjects: [
            [] as T3CodeProjectApi[],
            {
                setMachine: () => [],
                loadProjectsSuccess: () => [],
                loadMoreProjectsSuccess: (state, { moreProjectsResult }) =>
                    moreProjectsResult?.status === 'ok' ? [...state, ...(moreProjectsResult.projects ?? [])] : state,
            },
        ],
        // A new id for each first-page load, so a later page asked for an earlier list never lands on this one.
        projectListId: [0, { setMachine: (id) => id + 1, loadProjects: (id) => id + 1 }],
        nextCursor: [
            null as number | null,
            {
                setMachine: () => null,
                loadProjectsSuccess: (_, { projectsResult }) =>
                    projectsResult?.status === 'ok' ? (projectsResult.next_cursor ?? null) : null,
                loadMoreProjectsSuccess: (state, { moreProjectsResult }) =>
                    moreProjectsResult?.status === 'ok' ? (moreProjectsResult.next_cursor ?? null) : state,
            },
        ],
        taskResult: { setMachine: () => null, setProject: () => null, createTaskFailure: () => null },
        error: [
            null as string | null,
            {
                setMachine: () => null,
                setProject: () => null,
                loadMachines: () => null,
                loadProjects: () => null,
                loadMoreProjects: () => null,
                createTask: () => null,
                loadMachinesFailure: (_, { errorObject }) =>
                    errorDetail(errorObject, "PostHog couldn't load your T3 Code connections. Try again."),
                loadProjectsFailure: (_, { errorObject }) =>
                    errorDetail(errorObject, "PostHog couldn't load the projects on this machine. Try again."),
                loadMoreProjectsFailure: (_, { errorObject }) =>
                    errorDetail(errorObject, "PostHog couldn't load more projects from this machine. Try again."),
                createTaskFailure: (_, { errorObject }) =>
                    errorDetail(errorObject, "PostHog couldn't create the task in T3 Code. Try again."),
            },
        ],
    }),
    selectors({
        projects: [
            (s) => [s.projectsResult, s.laterProjects],
            (projectsResult: T3CodeProjectsApi | null, laterProjects: T3CodeProjectApi[]): T3CodeProjectApi[] | null =>
                projectsResult?.status === 'ok' ? [...(projectsResult.projects ?? []), ...laterProjects] : null,
        ],
        pendingApproval: [
            (s) => [s.projectsResult, s.moreProjectsResult, s.taskResult],
            (
                projectsResult: T3CodeProjectsApi | null,
                moreProjectsResult: T3CodeProjectsApi | null,
                taskResult: T3CodeWebhookTaskApi | null
            ): T3CodePendingApproval | null => {
                if (taskResult?.status === 'needs_approval' && taskResult.approval_token) {
                    return { kind: 'task', approvalToken: taskResult.approval_token }
                }
                if (projectsResult?.status === 'needs_approval' && projectsResult.approval_token) {
                    return { kind: 'projects', approvalToken: projectsResult.approval_token }
                }
                if (moreProjectsResult?.status === 'needs_approval' && moreProjectsResult.approval_token) {
                    return { kind: 'more-projects', approvalToken: moreProjectsResult.approval_token }
                }
                return null
            },
        ],
        createdWebhookUrl: [
            (s) => [s.taskResult],
            (taskResult: T3CodeWebhookTaskApi | null): string | null =>
                taskResult?.status === 'ok' ? (taskResult.webhook_url ?? null) : null,
        ],
        callInFlight: [
            (s) => [s.projectsResultLoading, s.moreProjectsResultLoading, s.taskResultLoading],
            (projectsLoading: boolean, moreProjectsLoading: boolean, taskLoading: boolean): boolean =>
                projectsLoading || moreProjectsLoading || taskLoading,
        ],
        selectionDisabledReason: [
            (s) => [s.taskResultLoading],
            (taskLoading: boolean): string | null => (taskLoading ? 'Wait until the task is created' : null),
        ],
        projectHelp: [
            (s) => [s.projects, s.nextCursor],
            (projects: T3CodeProjectApi[] | null, nextCursor: number | null): T3CodeProjectHelp | null => {
                if (!projects?.length) {
                    return null
                }
                if (nextCursor !== null) {
                    return 'more-projects'
                }
                return projects.every(({ has_default_model }) => !has_default_model) ? 'no-default-model' : null
            },
        ],
        projectDisabledReason: [
            (s) => [s.selectionDisabledReason, s.projects, s.projectsResultLoading, s.pendingApproval],
            (
                selectionDisabledReason: string | null,
                projects: T3CodeProjectApi[] | null,
                projectsLoading: boolean,
                pendingApproval: T3CodePendingApproval | null
            ): string | null => {
                if (selectionDisabledReason || projects !== null || projectsLoading) {
                    return selectionDisabledReason
                }
                return pendingApproval?.kind === 'projects'
                    ? "Allow PostHog to read this machine's projects first"
                    : "PostHog couldn't load this machine's projects"
            },
        ],
        retry: [
            (s) => [s.machines, s.machine, s.projects],
            (
                machines: T3CodeMachineApi[] | null,
                machine: string | null,
                projects: T3CodeProjectApi[] | null
            ): T3CodeRetry | null => {
                if (machines === null) {
                    return 'machines'
                }
                return machine && projects === null ? 'projects' : null
            },
        ],
        createTaskDisabledReason: [
            (s) => [s.machine, s.project],
            (machine: string | null, project: string | null): string | null =>
                !machine ? 'Choose a machine' : !project ? 'Choose a project' : null,
        ],
    }),
    listeners(({ actions, values, props }) => ({
        setMachine: ({ machine }) => {
            if (machine) {
                actions.loadProjects(undefined)
            }
        },
        allowPendingCall: () => {
            const pending = values.pendingApproval
            if (pending?.kind === 'projects') {
                actions.loadProjects(pending.approvalToken)
            } else if (pending?.kind === 'more-projects') {
                actions.loadMoreProjects(pending.approvalToken)
            } else if (pending?.kind === 'task' && values.taskTitle) {
                actions.createTask({ title: values.taskTitle, approvalToken: pending.approvalToken })
            }
        },
        createTaskSuccess: ({ taskResult }) => {
            if (taskResult?.status === 'ok' && taskResult.webhook_url) {
                props.onWebhookUrl(taskResult.webhook_url)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadMachines()
    }),
])
