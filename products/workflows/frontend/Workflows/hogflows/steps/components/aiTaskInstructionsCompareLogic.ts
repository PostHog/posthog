import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'

import { hogFlowsRevisionsList, hogFlowsRevisionsRetrieve } from '../../../../generated/api'
import type {
    HogFlowRevisionApi,
    HogFlowRevisionBasicApi,
    PaginatedHogFlowRevisionBasicListApi,
} from '../../../../generated/api.schemas'
import { getAiTaskPrompt, isAiTaskStep } from '../../../workflowLogic'
import type { HogFlow, HogFlowAction } from '../../types'

export interface AiTaskInstructionsCompareLogicProps {
    workflowId: string
    actionId: string
}

/** The step's instructions in a list of actions, or null when the step is not an AI task there. */
export function findAiTaskPrompt(actions: HogFlowAction[] | undefined, actionId: string): string | null {
    const action = actions?.find((candidate) => candidate.id === actionId)
    return action && isAiTaskStep(action) ? getAiTaskPrompt(action) : null
}

