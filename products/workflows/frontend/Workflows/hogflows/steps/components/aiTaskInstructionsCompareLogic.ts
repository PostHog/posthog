/** The step's instructions in a list of actions, or null when the step is not an AI task there. */
export function findAiTaskPrompt(actions: HogFlowAction[] | undefined, actionId: string): string | null {
    // Version snapshots are stored as loose JSON, so every level is checked before use.
    const action = Array.isArray(actions) ? actions.find((candidate) => candidate?.id === actionId) : undefined
    if (action?.type !== 'function' || action.config?.template_id !== 'template-posthog-create-task') {
        return null
    }
    const value = action.config.inputs?.prompt?.value
    // A prompt written through the API can use CRLF line endings, and the editor saves LF. The diff
    // cannot show that difference, so it must not count as a change.
    return typeof value === 'string' ? value.replace(/\r\n?/g, '\n') : ''
}

type CompareTrigger = 'open' | 'select_version'

function captureCompared(workflowId: string, version: number | null, trigger: CompareTrigger): void {
    // pinned: analytics event name
    posthog.capture('workflows ai task instructions compared', {
        workflow_id: workflowId,
        compared_version: version === null ? 'live' : String(version),
        trigger,
    })
}

