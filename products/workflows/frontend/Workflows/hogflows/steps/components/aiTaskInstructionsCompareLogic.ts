export type aiTaskInstructionsCompareLogicType = MakeLogicType<
    aiTaskInstructionsCompareLogicValues,
    aiTaskInstructionsCompareLogicActions,
    AiTaskInstructionsCompareLogicProps,
    aiTaskInstructionsCompareLogicMeta
>

export const aiTaskInstructionsCompareLogic = kea<aiTaskInstructionsCompareLogicType>([
    path((key) => [
        'products',
        'workflows',
        'frontend',
        'Workflows',
        'hogflows',
        'steps',
        'components',
        'aiTaskInstructionsCompareLogic',
        key,
    ]),
    props({} as AiTaskInstructionsCompareLogicProps),
    key(({ workflowId, actionId }) => `${workflowId}:${actionId}`),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
    })),
    actions({
        setOpen: (open: boolean) => ({ open }),
        // null compares with the live version, which the editor already holds.
        selectVersion: (version: number | null) => ({ version }),
    }),
    reducers({
        isOpen: [false, { setOpen: (_, { open }) => open }],
        selectedVersion: [null as number | null, { selectVersion: (_, { version }) => version }],
        revisionLoadFailed: [
            false,
            {
                loadRevision: () => false,
                loadRevisionFailure: () => true,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        revisionsResponse: [
            null as PaginatedHogFlowRevisionBasicListApi | null,
            {
                loadRevisions: async () =>
                    await hogFlowsRevisionsList(String(values.currentTeamIdStrict), props.workflowId),
            },
        ],
        revision: [
            null as HogFlowRevisionApi | null,
            {
                loadRevision: async (version: number) =>
                    await hogFlowsRevisionsRetrieve(String(values.currentTeamIdStrict), props.workflowId, version),
            },
        ],
    })),
    selectors({
        revisions: [
            (s) => [s.revisionsResponse],
            (response: PaginatedHogFlowRevisionBasicListApi | null): HogFlowRevisionBasicApi[] =>
                response?.results ?? [],
        ],
        // undefined while the chosen version loads, and null when the step is not an AI task in it.
        selectedRevisionPrompt: [
            (s) => [s.selectedVersion, s.revision, (_, props) => props.actionId],
            (
                selectedVersion: number | null,
                revision: HogFlowRevisionApi | null,
                actionId: string
            ): string | null | undefined =>
                selectedVersion === null || revision?.version !== selectedVersion
                    ? undefined
                    : findAiTaskPrompt((revision.content as Partial<HogFlow> | null)?.actions, actionId),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        setOpen: ({ open }) => {
            if (!open) {
                return
            }
            if (!values.revisionsResponse && !values.revisionsResponseLoading) {
                actions.loadRevisions()
            }
            // pinned: analytics event name
            posthog.capture('workflows ai task instructions compared', {
                workflow_id: props.workflowId,
                compared_version: values.selectedVersion ?? 'live',
            })
        },
        selectVersion: ({ version }) => {
            if (version !== null) {
                actions.loadRevision(version)
            }
            // pinned: analytics event name
            posthog.capture('workflows ai task instructions compared', {
                workflow_id: props.workflowId,
                compared_version: version ?? 'live',
            })
        },
    })),
])
