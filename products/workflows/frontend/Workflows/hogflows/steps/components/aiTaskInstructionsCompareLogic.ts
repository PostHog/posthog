export const aiTaskInstructionsCompareLogic = kea<aiTaskInstructionsCompareLogicType>([
    path((key) => [
        'products',
        'workflows',
        'frontend',
        'Workflows',
        'hogflows',
        'steps',
        'components',
        'aiTaskInstructionsCompareLogic',
        key,
    ]),
    props({} as AiTaskInstructionsCompareLogicProps),
    key(({ workflowId, actionId }) => `${workflowId}:${actionId}`),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
    })),
    actions({
        // With newestPastBelow set, the panel opens on the newest version below it once the list loads.
        setOpen: (open: boolean, newestPastBelow: number | null = null) => ({ open, newestPastBelow }),
        // null compares with the live version, which the editor already holds.
        selectVersion: (version: number | null, trigger: CompareTrigger = 'select_version') => ({ version, trigger }),
    }),
    reducers({
        isOpen: [false, { setOpen: (_, { open }) => open }],
        selectedVersion: [null as number | null, { selectVersion: (_, { version }) => version }],
        revisionLoadFailed: [
            false,
            {
                selectVersion: () => false,
                loadRevision: () => false,
                loadRevisionFailure: () => true,
            },
        ],
        revisionsLoadFailed: [
            false,
            {
                loadRevisions: () => false,
                loadRevisionsFailure: () => true,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        revisionsResponse: [
            null as PaginatedHogFlowRevisionBasicListApi | null,
            {
                // 500 is the endpoint's page limit.
                loadRevisions: async () =>
                    await hogFlowsRevisionsList(String(values.currentTeamIdStrict), props.workflowId, { limit: 500 }),
            },
        ],
        revision: [
            null as HogFlowRevisionApi | null,
            {
                loadRevision: async (version: number, breakpoint) => {
                    // A response for a version the user has since moved away from must not land, whether it
                    // succeeded or failed, so each call checks the breakpoint once its request settles.
                    try {
                        const revision = await hogFlowsRevisionsRetrieve(
                            String(values.currentTeamIdStrict),
                            props.workflowId,
                            version
                        )
                        breakpoint()
                        return revision
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
    })),
    selectors({
        revisions: [
            (s) => [s.revisionsResponse],
            (response: PaginatedHogFlowRevisionBasicListApi | null): HogFlowRevisionBasicApi[] =>
                response?.results ?? [],
        ],
        revisionOptions: [
            (s) => [s.revisions],
            (revisions: HogFlowRevisionBasicApi[]): { value: number; label: string; labelInMenu: string }[] =>
                revisions.map((revision) => ({
                    value: revision.version,
                    label: `v${revision.version}`,
                    labelInMenu: `v${revision.version} · ${dayjs(revision.created_at).format('MMM D, YYYY, h:mm A')}`,
                })),
        ],
        // undefined while the chosen version loads, and null when the step is not an AI task in it.
        selectedRevisionPrompt: [
            (s) => [s.selectedVersion, s.revision, (_, props) => props.actionId],
            (
                selectedVersion: number | null,
                revision: HogFlowRevisionApi | null,
                actionId: string
            ): string | null | undefined =>
                selectedVersion === null || revision?.version !== selectedVersion
                    ? undefined
                    : findAiTaskPrompt((revision.content as Partial<HogFlow> | null)?.actions, actionId),
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        setOpen: ({ open, newestPastBelow }) => {
            if (!open) {
                cache.newestPastBelow = null
                return
            }
            // Reload on every open, because a publish since the last open adds a version.
            if (!values.revisionsResponseLoading) {
                actions.loadRevisions()
            }
            if (newestPastBelow !== null && values.selectedVersion === null) {
                cache.newestPastBelow = newestPastBelow
                return
            }
            captureCompared(props.workflowId, values.selectedVersion, 'open')
        },
        loadRevisionsSuccess: () => {
            const below: number | null = cache.newestPastBelow ?? null
            if (below === null) {
                return
            }
            cache.newestPastBelow = null
            // The list comes newest first.
            const newestPast = values.revisions.find((revision) => revision.version < below)
            if (newestPast && values.selectedVersion === null) {
                actions.selectVersion(newestPast.version, 'open')
            } else {
                captureCompared(props.workflowId, values.selectedVersion, 'open')
            }
        },
        loadRevisionsFailure: () => {
            if (cache.newestPastBelow != null) {
                cache.newestPastBelow = null
                captureCompared(props.workflowId, values.selectedVersion, 'open')
            }
        },
        selectVersion: ({ version, trigger }) => {
            // A version the user picks wins over the default that waits for the list.
            if (trigger === 'select_version') {
                cache.newestPastBelow = null
            }
            if (version !== null) {
                actions.loadRevision(version)
            }
            captureCompared(props.workflowId, version, trigger)
        },
    })),
])
