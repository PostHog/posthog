/**
 * Sends one real email from a workflow's email step to an address the user names, so the step can
 * be read in an inbox without narrowing the workflow's audience down to a single person first.
 *
 * The step's content is snapshotted when the modal opens and sent through a throwaway flow that
 * holds only this one email, so no other step in the workflow runs and nobody else is mailed.
 */
export const stepTestSendLogic = kea<stepTestSendLogicType>([
    path((key) => [
        'products',
        'workflows',
        'frontend',
        'Workflows',
        'hogflows',
        'steps',
        'components',
        'stepTestSendLogic',
        key,
    ]),
    props({} as WorkflowLogicProps),
    key(({ id }) => id ?? 'new'),

    connect((props: WorkflowLogicProps) => ({
        values: [
            workflowLogic(props),
            ['workflow'],
            hogFlowEditorTestLogic(props),
            ['sampleGlobals'],
            teamLogic,
            ['currentTeamId'],
            userLogic,
            ['user'],
        ],
    })),

    actions({
        openModal: (emailInput: CyclotronJobInputType | null) => ({ emailInput }),
        closeModal: true,
        setRecipientEmail: (email: string) => ({ email }),
        clearTestSendResult: true,
    }),

    reducers({
        isModalOpen: [false, { openModal: () => true, closeModal: () => false }],
        // Snapshotted on open rather than read live, so what the disabled reason judges is exactly
        // what the send carries.
        emailInput: [null as CyclotronJobInputType | null, { openModal: (_, { emailInput }) => emailInput ?? null }],
        recipientEmail: ['', { setRecipientEmail: (_, { email }) => email }],
    }),

    loaders(({ values }) => ({
        testSendResult: [
            null as HogflowTestResult | null,
            {
                clearTestSendResult: () => null,
                sendTestEmail: async (): Promise<HogflowTestResult> => {
                    const { emailInput, emailValue, recipientEmail, currentTeamId, workflow, sampleGlobals } = values

                    const configuration = buildSingleEmailTestFlow({
                        email: emailValue ?? {},
                        recipientEmail,
                        name: workflow?.name || 'Test email',
                        teamId: currentTeamId,
                        templating: emailInput?.templating === 'hog' ? 'hog' : 'liquid',
                    })

                    // The endpoint declares a fallback response serializer, so the generated client
                    // types this call's result as void - and the result is what tells a delivered
                    // test from a declined one.
                    // nosemgrep: prefer-codegen-api-namespaced-workflows
                    return await api.hogFlows.createTestInvocation('new', {
                        configuration,
                        // The event the test panel already loaded, so merge tags resolve to the
                        // values a real run would use rather than to invented ones.
                        globals:
                            sampleGlobals ??
                            createExampleEvent(
                                currentTeamId ?? undefined,
                                configuration.name,
                                '$pageview',
                                recipientEmail
                            ),
                        // A test send is a real send. Mocking it would defeat the point.
                        mock_async_functions: false,
                        current_action_id: TEST_EMAIL_ACTION_ID,
                    })
                },
            },
        ],
    })),

    selectors({
        emailValue: [
            (s) => [s.emailInput],
            (emailInput: CyclotronJobInputType | null): Record<string, any> | null => emailInput?.value ?? null,
        ],
        previewPersonName: [
            (s) => [s.sampleGlobals],
            (sampleGlobals: CyclotronJobInvocationGlobals | null): string | null => sampleGlobals?.person?.name ?? null,
        ],
        testSendSkipReason: [
            (s) => [s.testSendResult],
            (testSendResult: HogflowTestResult | null): string | undefined => findTestSendSkipReason(testSendResult),
        ],
        sendDisabledReason: [
            (s) => [s.emailValue, s.recipientEmail],
            (emailValue: Record<string, any> | null, recipientEmail: string): string | undefined => {
                if (!emailValue?.from?.integrationId) {
                    return 'Choose an email sender first'
                }
                if (!emailValue?.subject) {
                    return 'Add a subject first'
                }
                if (!emailValue?.html && !emailValue?.text) {
                    return 'Add email content first'
                }
                if (!recipientEmail || !isEmail(recipientEmail)) {
                    return 'Enter a valid email address'
                }
                return undefined
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        openModal: () => {
            // A stale result from a previous attempt must not greet the next one.
            actions.clearTestSendResult()
            if (!values.recipientEmail && values.user?.email) {
                actions.setRecipientEmail(values.user.email)
            }
        },
        sendTestEmailSuccess: ({ testSendResult }) => {
            // A declined send finishes the step cleanly, so check the reason before the status.
            if (values.testSendSkipReason) {
                lemonToast.warning('Nothing was sent, see why below')
            } else if (testSendResult?.status === 'success') {
                lemonToast.success(`Test email sent to ${values.recipientEmail}`)
                actions.closeModal()
            } else if (testSendResult?.status === 'skipped') {
                lemonToast.warning('The email step was skipped, so nothing was sent')
            } else {
                lemonToast.error('Could not send the test email')
            }
        },
        sendTestEmailFailure: () => {
            lemonToast.error('Could not send the test email')
        },
    })),
])
