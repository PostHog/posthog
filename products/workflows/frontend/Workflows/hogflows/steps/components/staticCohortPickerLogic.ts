export const staticCohortPickerLogic = kea<staticCohortPickerLogicType>([
    props({} as StaticCohortPickerProps),
    key((props) => props.id),
    path((key) => [
        'products',
        'workflows',
        'frontend',
        'Workflows',
        'hogflows',
        'steps',
        'components',
        'staticCohortPickerLogic',
        key,
    ]),
    actions({
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        loadMoreCohorts: true,
        loadCohortById: (id: number) => ({ id }),
    }),
    loaders(({ values }) => ({
        cohortPage: [
            null as StaticCohortPage | null,
            {
                loadCohortPage: async (
                    { search, offset }: { search: string; offset: number },
                    breakpoint
                ): Promise<StaticCohortPage> => {
                    const response = await cohortsList(String(getCurrentTeamId()), {
                        basic: true,
                        type: 'static',
                        search: search || undefined,
                        limit: COHORTS_PAGE_SIZE,
                        offset,
                    })
                    breakpoint()
                    return {
                        results:
                            offset === 0
                                ? response.results
                                : [...(values.cohortPage?.results ?? []), ...response.results],
                        next: response.next ?? null,
                        offset,
                        search,
                    }
                },
            },
        ],
        selectedCohorts: [
            {} as Record<number, CohortApi | null>,
            {
                loadCohortById: async ({ id }) => {
                    if (id in values.selectedCohorts) {
                        return values.selectedCohorts
                    }
                    try {
                        const cohort = await cohortsRetrieve(String(getCurrentTeamId()), id)
                        return {
                            ...values.selectedCohorts,
                            [id]: cohort.is_static && !cohort.deleted ? cohort : null,
                        }
                    } catch {
                        return { ...values.selectedCohorts, [id]: null }
                    }
                },
            },
        ],
    })),
    reducers({
        searchTerm: [
            '',
            {
                setSearchTerm: (_, { searchTerm }) => searchTerm,
            },
        ],
    }),
    selectors({
        visibleCohorts: [
            (s) => [s.cohortPage, s.selectedCohorts, s.searchTerm],
            (
                cohortPage: StaticCohortPage | null,
                selectedCohorts: Record<number, CohortApi | null>,
                searchTerm: string
            ): CohortApi[] => {
                const cohortsById = new Map<number, CohortApi>()
                if (cohortPage?.search === searchTerm) {
                    for (const cohort of cohortPage.results) {
                        cohortsById.set(cohort.id, cohort)
                    }
                }
                for (const cohort of Object.values(selectedCohorts)) {
                    if (cohort) {
                        cohortsById.set(cohort.id, cohort)
                    }
                }
                return [...cohortsById.values()]
            },
        ],
        hasMoreCohorts: [
            (s) => [s.cohortPage, s.searchTerm],
            (cohortPage: StaticCohortPage | null, searchTerm: string): boolean =>
                cohortPage?.search === searchTerm && cohortPage.next !== null,
        ],
    }),
    listeners(({ actions, values }) => ({
        setSearchTerm: async (_, breakpoint) => {
            await breakpoint(SEARCH_DEBOUNCE_MS)
            actions.loadCohortPage({ search: values.searchTerm, offset: 0 })
        },
        loadMoreCohorts: () => {
            if (values.hasMoreCohorts && !values.cohortPageLoading) {
                actions.loadCohortPage({ search: values.searchTerm, offset: values.cohortPage?.results.length ?? 0 })
            }
        },
        loadCohortPageFailure: () => {
            lemonToast.error("Couldn't load static cohorts. Try again.")
        },
    })),
    afterMount(({ actions, props }) => {
        actions.loadCohortPage({ search: '', offset: 0 })
        if (props.selectedCohortId) {
            actions.loadCohortById(props.selectedCohortId)
        }
    }),
    propsChanged(({ actions, props }, oldProps) => {
        if (props.selectedCohortId && props.selectedCohortId !== oldProps.selectedCohortId) {
            actions.loadCohortById(props.selectedCohortId)
        }
    }),
])
