import { MakeLogicType, afterMount, connect, kea, key, path, props, propsChanged, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { objectsEqual } from 'lib/utils/objects'
import {
    flagCallsDailyCountQuery,
    flagCallsMatchingFilters,
    storesFlagCallsOutsideEvents,
    withFlagCallCounts,
} from 'scenes/hog-functions/filters/flagCallsMatching'
import { teamLogic } from 'scenes/teamLogic'

import { performQuery } from '~/queries/query'
import { TeamPublicType, TeamType, TrendResult } from '~/types'

import { EventTriggerFilters, TRIGGER_VOLUME_DAYS, eventTriggerVolumeQuery } from './triggerVolume'

export type TriggerVolume = {
    /** Events matched over the whole window. */
    total: number
    /** One count per day, oldest first. */
    daily: number[]
    /** One label per daily count, for the chart tooltip. */
    labels: string[]
    /** Average matches per day over the window. */
    perDay: number
    /** Matches on the busiest day of the window. */
    peakPerDay: number
}

export interface TriggerVolumeLogicProps {
    /** Trigger action id, so each trigger keeps its own estimate. */
    id: string
    filters: EventTriggerFilters | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface triggerVolumeLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    volume: TriggerVolume | null
    volumeFailed: boolean
    volumeLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface triggerVolumeLogicActions {
    loadVolume: (_: void) => void
    loadVolumeFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadVolumeSuccess: (
        volume: TriggerVolume | null,
        payload?: void
    ) => {
        volume: TriggerVolume | null
        payload?: void
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface triggerVolumeLogicMeta {
    key: string
}

export type triggerVolumeLogicType = MakeLogicType<
    triggerVolumeLogicValues,
    triggerVolumeLogicActions,
    TriggerVolumeLogicProps,
    triggerVolumeLogicMeta
>

export const triggerVolumeLogic = kea<triggerVolumeLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'hogflows', 'steps', 'triggerVolumeLogic']),
    props({} as TriggerVolumeLogicProps),
    key(({ id }) => `trigger-volume-logic-${id}`),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
    })),
    reducers(() => ({
        volumeFailed: [
            false,
            {
                loadVolume: () => false,
                loadVolumeSuccess: () => false,
                loadVolumeFailure: () => true,
            },
        ],
    })),
    loaders(({ props, values }) => ({
        volume: [
            null as TriggerVolume | null,
            {
                loadVolume: async (_: void, breakpoint): Promise<TriggerVolume | null> => {
                    if (!props.filters) {
                        return null
                    }
                    // Every filter edit asks for a new count, so wait out a burst of typing. The
                    // first estimate of a trigger waits far less, since there is nothing to show yet.
                    await breakpoint(values.volume === null ? 100 : 1000)
                    const flagCallFilters = storesFlagCallsOutsideEvents(values.currentTeam)
                        ? flagCallsMatchingFilters(props.filters)
                        : null
                    const [response, flagCallsResponse] = await Promise.all([
                        performQuery(eventTriggerVolumeQuery(props.filters)),
                        flagCallFilters
                            ? performQuery(
                                  flagCallsDailyCountQuery(
                                      flagCallFilters,
                                      props.filters.filter_test_accounts,
                                      TRIGGER_VOLUME_DAYS
                                  )
                              )
                            : null,
                    ])
                    breakpoint()

                    const series = response.results?.[0]
                    const { data: daily, count: total } =
                        series && flagCallsResponse
                            ? withFlagCallCounts(series as TrendResult, flagCallsResponse.results as [string, number][])
                            : { data: (series?.data ?? []) as number[], count: (series?.count ?? 0) as number }
                    // Divide by the days the response actually carries, so a range that resolves to
                    // a different number of buckets than asked for cannot skew the average.
                    const days = daily.length || TRIGGER_VOLUME_DAYS
                    return {
                        total,
                        daily,
                        labels: series?.labels ?? [],
                        perDay: Math.round(total / days),
                        peakPerDay: daily.length ? Math.max(...daily) : 0,
                    }
                },
            },
        ],
    })),
    propsChanged(({ actions, props }, oldProps) => {
        if (!oldProps || !objectsEqual(props.filters, oldProps.filters)) {
            actions.loadVolume()
        }
    }),
    afterMount(({ actions }) => {
        actions.loadVolume()
    }),
])
