import { MakeLogicType, kea, key, listeners, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import api, { ApiError } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast'

import { CohortType } from '~/types'

export interface BatchAudienceCsvLogicProps {
    /** Trigger action id, so each trigger keeps its own upload state. */
    id: string
    /** Runs once the uploaded file has become a static cohort. */
    onCohortCreated: (cohort: CohortType) => void
}

export function cohortNameFromFile(fileName: string): string {
    return fileName.replace(/\.[^./\\]+$/, '').trim() || 'Uploaded list'
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface batchAudienceCsvLogicValues {
    uploadedCohort: CohortType | null
    uploadedCohortLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface batchAudienceCsvLogicActions {
    uploadCsv: (file: File) => File
    uploadCsvFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    uploadCsvSuccess: (
        uploadedCohort: CohortType,
        payload?: File
    ) => {
        uploadedCohort: CohortType
        payload?: File
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface batchAudienceCsvLogicMeta {
    key: string
}

export type batchAudienceCsvLogicType = MakeLogicType<
    batchAudienceCsvLogicValues,
    batchAudienceCsvLogicActions,
    BatchAudienceCsvLogicProps,
    batchAudienceCsvLogicMeta
>

export const batchAudienceCsvLogic = kea<batchAudienceCsvLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'hogflows', 'steps', 'batchAudienceCsvLogic']),
    props({} as BatchAudienceCsvLogicProps),
    key(({ id }) => `batch-audience-csv-${id}`),
    loaders(() => ({
        uploadedCohort: [
            null as CohortType | null,
            {
                uploadCsv: async (file: File) => {
                    const formData = new FormData()
                    formData.append('name', cohortNameFromFile(file.name))
                    formData.append('is_static', 'true')
                    formData.append('filters', JSON.stringify({ properties: {} }))
                    formData.append('csv', file)
                    return await api.cohorts.create(formData as unknown as Partial<CohortType>)
                },
            },
        ],
    })),
    listeners(({ props }) => ({
        uploadCsvSuccess: ({ uploadedCohort }) => {
            props.onCohortCreated(uploadedCohort)
            lemonToast.success(
                `Added "${uploadedCohort.name}" to the audience. It can take a few minutes for everyone in the file to show up.`
            )
        },
        uploadCsvFailure: ({ error, errorObject }) => {
            const apiError = errorObject as ApiError | undefined
            lemonToast.error(apiError?.detail || error || 'Could not build an audience from that file')
        },
    })),
])
