export function getAudienceDedupeKey(workflow?: { actions?: HogFlowAction[] } | null): 'email' | undefined {
    // Mirrors the backend (`canDedupeByEmail` in `nodejs/src/cdp/cdp-api.ts`): batch sends dedupe by
    // email only when every email action sends to the default `{{ person.properties.email }}` recipient.
    const emailActions = workflow?.actions?.filter((action) => action.type === 'function_email') ?? []
    if (emailActions.length === 0) {
        return undefined
    }
    const allDefault = emailActions.every((action) => {
        // Any other recipient (custom property, computed Liquid, static address) makes the dedupe key
        // diverge from the actual send target, so dedupe is skipped rather than applied wrongly.
        return recipientEmailProperty((action as any)?.config?.inputs?.email?.value?.to?.email) === 'email'
    })
    return allDefault ? 'email' : undefined
}

export function hogFlowSendsEmail(workflow?: { actions?: HogFlowAction[] } | null): boolean {
    // The tiered batch audience limit only applies to workflows with an email step; SMS, push,
    // and webhook batches keep the flat limit. Mirrors hog_flow_sends_email on the backend:
    // the worker executes function steps by template, so the email template counts as an email
    // step regardless of the declared action type.
    return (workflow?.actions ?? []).some(
        (action) => action.type === 'function_email' || (action as any)?.config?.template_id === 'template-email'
    )
}

export interface BatchTriggerLogicProps {
    id?: string | 'new'
    filters?: Extract<HogFlowAction['config'], { type: 'batch' }>['filters']
    /** When 'email', the count reflects unique email addresses, matching batch send dedup. */
    dedupeKey?: 'email'
    /** Whether the workflow contains an email step, which decides if the tiered audience limit applies. */
    sendsEmail?: boolean
    /** Person properties the email steps send to. Each costs one extra audience query, so pass them only where shown. */
    recipientEmailProperties?: string[]
    /** Called when a realtime cohort shares the audience with other conditions, so the caller can drop them. */
    onRealtimeCohortWithOtherConditions?: (cohortId: number) => void
}

