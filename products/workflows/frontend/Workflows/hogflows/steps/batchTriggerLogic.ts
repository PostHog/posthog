async function requestBlastRadius(
    projectId: number | null,
    props: BatchTriggerLogicProps
): Promise<BlastRadiusApi | null> {
    if (!projectId || !props.filters) {
        return null
    }
    return await hogFlowsUserBlastRadiusCreate(String(projectId), {
        filters: props.filters,
        dedupe_key: props.dedupeKey ?? null,
        sends_email: props.sendsEmail ?? true,
    })
}

export const batchTriggerLogic = kea<batchTriggerLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'hogflows', 'steps', 'batchTriggerLogic']),
    props({} as BatchTriggerLogicProps),
    key(({ id }) => `batch-trigger-logic-${id || 'new'}`),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        loadBlastRadius: true,
        setBlastRadiusError: (error: string | null) => ({ error }),
    }),
    reducers(() => ({
        filters: {
            setFilters: (_, { filters }) => filters,
        },
        blastRadiusError: [
            null as string | null,
            {
                loadBlastRadius: () => null,
                setBlastRadiusError: (_, { error }) => error,
            },
        ],
    })),
    loaders(({ props, values }) => ({
        recipientsWithoutEmail: [
            {} as Record<string, number>,
            {
                loadRecipientsWithoutEmail: async (_, breakpoint) => {
                    const filters = props.filters
                    const projectId = values.currentProjectId
                    // An unfiltered audience's size is a cached total; this count would scan every person.
                    if (
                        !projectId ||
                        !filters ||
                        filters.audience_type === 'accounts' ||
                        !filters.properties?.length ||
                        !props.recipientEmailProperties?.length
                    ) {
                        return {}
                    }
                    const counts = await Promise.all(
                        props.recipientEmailProperties.map(async (key): Promise<[string, number] | null> => {
                            try {
                                const missing = await hogFlowsUserBlastRadiusCreate(String(projectId), {
                                    filters: {
                                        ...filters,
                                        properties: [
                                            ...(filters.properties ?? []),
                                            { key, type: 'person', operator: 'is_not_set' },
                                        ],
                                    },
                                    sends_email: props.sendsEmail,
                                })
                                return [key, missing.affected]
                            } catch {
                                // A failed check must not block the run; it only drops the warning.
                                return null
                            }
                        })
                    )
                    breakpoint()
                    return Object.fromEntries(counts.filter((count): count is [string, number] => count !== null))
                },
            },
        ],
        blastRadius: [
            null as BlastRadiusApi | null,
            {
                loadBlastRadius: async () => {
                    return await requestBlastRadius(values.currentProjectId, props)
                },
            },
        ],
    })),
    reducers({
        blastRadius: {
            // A stale result would keep a realtime cohort's restrictions on an audience that no longer has one.
            loadBlastRadiusFailure: () => null,
        },
    }),
    listeners(({ actions, props, values }) => ({
        loadBlastRadius: () => {
            actions.loadRecipientsWithoutEmail(null)
        },
        loadBlastRadiusSuccess: async ({ blastRadius }, breakpoint) => {
            const mixed = blastRadius?.realtime_cohort_with_other_conditions
            if (mixed) {
                props.onRealtimeCohortWithOtherConditions?.(mixed.id)
            }
            // Run reads the realtime cohort's status from the audience size, and the cohort can finish or recover
            // while the popover stays open. Only the size is refreshed, not the recipient check.
            if (!props.filters || !isRealtimeCohortUnresolved(blastRadius?.realtime_cohort)) {
                return
            }
            for (;;) {
                await breakpoint(REALTIME_COHORT_STATUS_POLL_MS)
                let refreshed: BlastRadiusApi | null = null
                try {
                    refreshed = await requestBlastRadius(values.currentProjectId, props)
                } catch {
                    // A failed check tries again on the next interval.
                }
                breakpoint()
                if (refreshed) {
                    actions.loadBlastRadiusSuccess(refreshed)
                    return
                }
            }
        },
        loadBlastRadiusFailure: ({ errorObject }) => {
            const apiError = errorObject as ApiError | undefined
            const message =
                apiError?.detail ||
                (errorObject as Error | undefined)?.message ||
                "Couldn't validate audience size. Your filters may not be supported."
            actions.setBlastRadiusError(message)
        },
    })),
    propsChanged(({ actions, props }, oldProps) => {
        if (
            !oldProps ||
            !objectsEqual(props.filters, oldProps.filters) ||
            props.dedupeKey !== oldProps.dedupeKey ||
            props.sendsEmail !== oldProps.sendsEmail
        ) {
            actions.loadBlastRadius()
        } else if (!objectsEqual(props.recipientEmailProperties, oldProps.recipientEmailProperties)) {
            actions.loadRecipientsWithoutEmail(null)
        }
    }),
    afterMount(({ actions }) => {
        actions.loadBlastRadius()
    }),
])
