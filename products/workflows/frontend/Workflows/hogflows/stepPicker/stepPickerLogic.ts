export const stepPickerLogic: LogicWrapper<stepPickerLogicType> = kea<stepPickerLogicType>([
    props({} as StepPickerLogicProps),
    key((props) => props.surface),
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'hogflows', 'stepPicker', 'stepPickerLogic', key]),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            teamLogic,
            ['currentTeam'],
            hogFunctionTemplateListLogic(DESTINATION_TEMPLATES_PROPS),
            ['templates'],
            stepPickerPreferencesLogic,
            ['favoriteStepIds', 'recentStepIds'],
        ],
        actions: [
            hogFunctionTemplateListLogic(DESTINATION_TEMPLATES_PROPS),
            ['loadHogFunctionTemplates', 'loadHogFunctionTemplatesSuccess', 'loadHogFunctionTemplatesFailure'],
            stepPickerPreferencesLogic,
            ['toggleFavoriteStep', 'recordRecentStep'],
        ],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        clearSearch: true,
        setView: (view: StepPickerView) => ({ view }),
        openProvider: (providerId: string) => ({ providerId }),
        closeProvider: true,
        selectStep: (stepId: string) => ({ stepId }),
        pickStep: (entry: StepCatalogEntry, via: StepPickerPickVia) => ({ entry, via }),
        toggleFavorite: (entry: StepCatalogEntry) => ({ entry }),
    }),
    reducers({
        search: [
            '',
            {
                setSearch: (_, { search }) => search,
                clearSearch: () => '',
                setView: () => '',
            },
        ],
        view: [
            'all' as StepPickerView,
            {
                setView: (_, { view }) => view,
            },
        ],
        openProviderId: [
            null as string | null,
            {
                openProvider: (_, { providerId }) => providerId,
                closeProvider: () => null,
                setView: () => null,
            },
        ],
        selectedStepId: [
            null as string | null,
            {
                selectStep: (_, { stepId }) => stepId,
                setSearch: () => null,
                clearSearch: () => null,
                setView: () => null,
                openProvider: () => null,
                closeProvider: () => null,
            },
        ],
        picked: [
            false,
            {
                pickStep: () => true,
            },
        ],
        templatesStatus: [
            'loading' as TemplatesStatus,
            {
                loadHogFunctionTemplates: () => 'loading',
                loadHogFunctionTemplatesSuccess: () => 'loaded',
                loadHogFunctionTemplatesFailure: () => 'failed',
            },
        ],
    }),
    selectors({
        isMainEnvironment: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): boolean =>
                !!currentTeam && currentTeam.id === currentTeam.project_id,
        ],
        destinationTemplates: [
            (s) => [s.templates, s.templatesStatus],
            (
                templates: HogFunctionTemplateWithSubTemplateType[],
                templatesStatus: TemplatesStatus
            ): HogFunctionTemplateType[] | null =>
                templates.length > 0 || templatesStatus === 'loaded' ? templates : null,
        ],
        templatesById: [
            (s) => [s.templates],
            (templates: HogFunctionTemplateType[]): Record<string, HogFunctionTemplateType> =>
                Object.fromEntries(templates.map((template) => [template.id, template])),
        ],
        isLoadingIntegrations: [
            (s) => [s.templatesStatus, s.destinationTemplates],
            (templatesStatus: TemplatesStatus, destinationTemplates: HogFunctionTemplateType[] | null): boolean =>
                templatesStatus === 'loading' && destinationTemplates === null,
        ],
        integrationsFailed: [
            (s) => [s.templatesStatus, s.destinationTemplates],
            (templatesStatus: TemplatesStatus, destinationTemplates: HogFunctionTemplateType[] | null): boolean =>
                templatesStatus === 'failed' && destinationTemplates === null,
        ],
        catalog: [
            (s) => [
                s.featureFlags,
                s.isMainEnvironment,
                s.destinationTemplates,
                (_, props) => props.isRowScopedTrigger,
            ],
            (
                featureFlags: FeatureFlagsSet,
                isMainEnvironment: boolean,
                destinationTemplates: HogFunctionTemplateType[] | null,
                isRowScopedTrigger
            ): StepCatalogEntry[] =>
                buildStepCatalog({ featureFlags, isMainEnvironment, isRowScopedTrigger, destinationTemplates }),
        ],
        providers: [(s) => [s.catalog], (catalog: StepCatalogEntry[]): StepProviderGroups => groupProviders(catalog)],
        visibleViews: [
            (s) => [s.catalog, s.favoriteStepIds, s.recentStepIds],
            (catalog: StepCatalogEntry[], favoriteStepIds: string[], recentStepIds: string[]): StepPickerView[] =>
                visibleViews(catalog, { favoriteStepIds, recentStepIds }),
        ],
        viewSteps: [
            (s) => [s.view, s.catalog, s.favoriteStepIds, s.recentStepIds],
            (
                view: StepPickerView,
                catalog: StepCatalogEntry[],
                favoriteStepIds: string[],
                recentStepIds: string[]
            ): StepCatalogEntry[] => stepsForView(view, catalog, { favoriteStepIds, recentStepIds }),
        ],
        isSearching: [(s) => [s.search], (search: string): boolean => search.trim().length > 0],
        searchResults: [
            (s) => [s.catalog, s.search, s.isSearching],
            (catalog: StepCatalogEntry[], search: string, isSearching: boolean): StepCatalogEntry[] =>
                isSearching ? searchSteps(catalog, search) : [],
        ],
        openedProvider: [
            (s) => [s.providers, s.openProviderId],
            (providers: StepProviderGroups, openProviderId: string | null): StepProvider | null =>
                [...providers.posthog, ...providers.thirdParty].find((provider) => provider.id === openProviderId) ??
                null,
        ],
        selectedStep: [
            (s) => [s.catalog, s.selectedStepId],
            (catalog: StepCatalogEntry[], selectedStepId: string | null): StepCatalogEntry | null =>
                catalog.find((entry) => entry.id === selectedStepId) ?? null,
        ],
    }),
    listeners(({ actions, props, values }) => ({
        setSearch: async ({ search }, breakpoint) => {
            await breakpoint(SEARCH_TRACKING_DEBOUNCE_MS)
            const query = search.trim()
            if (query && query === values.search.trim()) {
                // pinned: analytics event name and properties, renaming breaks dashboards
                posthog.capture('workflow step picker searched', {
                    surface: props.surface,
                    query: query.slice(0, MAX_TRACKED_QUERY_LENGTH),
                    result_count: values.searchResults.length,
                })
            }
        },
        setView: ({ view }) => {
            posthog.capture('workflow step picker view changed', { surface: props.surface, view })
        },
        openProvider: ({ providerId }) => {
            posthog.capture('workflow step picker provider opened', { surface: props.surface, provider: providerId })
        },
        pickStep: ({ entry, via }) => {
            posthog.capture('workflow step picker step picked', {
                surface: props.surface,
                step_id: entry.id,
                origin: entry.origin,
                product: entry.product,
                vendor: entry.vendor,
                category: entry.category,
                view: values.view,
                from_search: values.isSearching,
                via,
            })
            actions.recordRecentStep(entry.id)
            props.onPick(entry.action)
        },
        toggleFavorite: ({ entry }) => {
            posthog.capture('workflow step picker favorite toggled', {
                surface: props.surface,
                step_id: entry.id,
                favorite: !values.favoriteStepIds.includes(entry.id),
            })
            actions.toggleFavoriteStep(entry.id)
        },
    })),
    afterMount(({ actions, props }) => {
        posthog.capture('workflow step picker opened', { surface: props.surface })
        actions.loadHogFunctionTemplates()
    }),
    beforeUnmount(({ props, values }) => {
        posthog.capture('workflow step picker closed', { surface: props.surface, picked: values.picked })
    }),
])
