import { LogicWrapper, MakeLogicType, actions, kea, path, reducers } from 'kea'

import { getCurrentTeamIdOrNone, getCurrentUserIdOrNone } from 'lib/utils/getAppContext'

const MAX_RECENT_STEPS = 5

// kea-localstorage keys only by logic path, and favorites belong to one user in one project.
// Without both IDs nothing is persisted, so one account's list never shows to the next account on the browser.
function persistOptions(): { persist: true; prefix: string } | { persist: false } {
    const teamId = getCurrentTeamIdOrNone()
    const userId = getCurrentUserIdOrNone()
    return teamId && userId ? { persist: true, prefix: `${teamId}__${userId}__` } : { persist: false }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface stepPickerPreferencesLogicValues {
    favoriteStepIds: string[]
    recentStepIds: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface stepPickerPreferencesLogicActions {
    recordRecentStep: (stepId: string) => {
        stepId: string
    }
    toggleFavoriteStep: (stepId: string) => {
        stepId: string
    }
}

export type stepPickerPreferencesLogicType = MakeLogicType<
    stepPickerPreferencesLogicValues,
    stepPickerPreferencesLogicActions
>

export const stepPickerPreferencesLogic: LogicWrapper<stepPickerPreferencesLogicType> =
    kea<stepPickerPreferencesLogicType>([
        path([
            'products',
            'workflows',
            'frontend',
            'Workflows',
            'hogflows',
            'stepPicker',
            'stepPickerPreferencesLogic',
        ]),
        actions({
            toggleFavoriteStep: (stepId: string) => ({ stepId }),
            recordRecentStep: (stepId: string) => ({ stepId }),
        }),
        // pinned: persisted reducer names, key prefix and logic path are a storage contract, renaming drops saved lists
        reducers(() => ({
            favoriteStepIds: [
                [] as string[],
                persistOptions(),
                {
                    toggleFavoriteStep: (favorites, { stepId }) =>
                        favorites.includes(stepId)
                            ? favorites.filter((favorite) => favorite !== stepId)
                            : [...favorites, stepId],
                },
            ],
            recentStepIds: [
                [] as string[],
                persistOptions(),
                {
                    recordRecentStep: (recents, { stepId }) =>
                        [stepId, ...recents.filter((recent) => recent !== stepId)].slice(0, MAX_RECENT_STEPS),
                },
            ],
        })),
    ])
