export type surveyTriggerLogicType = MakeLogicType<
    surveyTriggerLogicValues,
    surveyTriggerLogicActions,
    SurveyTriggerProps,
    surveyTriggerLogicMeta
>

export const surveyTriggerLogic = kea<surveyTriggerLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'hogflows', 'registry', 'triggers', 'surveyTriggerLogic']),
    props({} as SurveyTriggerProps),
    actions({
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        loadSurveyById: (id: string) => ({ id }),
    }),
    loaders(({ values }) => ({
        surveys: [
            [] as Survey[],
            {
                loadSurveys: async () => {
                    const response = await api.surveys.list({ limit: SURVEYS_PAGE_SIZE, archived: false })
                    return response.results
                },
            },
        ],
        moreSurveys: [
            [] as Survey[],
            {
                loadMoreSurveys: async () => {
                    const response = await api.surveys.list({
                        limit: SURVEYS_PAGE_SIZE,
                        offset: values.allSurveys.length,
                        archived: false,
                    })
                    return response.results
                },
            },
        ],
        // Search runs server-side: a project can hold hundreds of surveys, so filtering only the
        // pages already loaded hides most of them from the picker.
        searchedSurveys: [
            [] as Survey[],
            {
                searchSurveys: async (searchTerm: string, breakpoint) => {
                    await breakpoint(SEARCH_DEBOUNCE_MS)
                    const search = searchTerm
                    if (!search) {
                        return []
                    }
                    const response = await api.surveys.list({
                        limit: SURVEYS_PAGE_SIZE,
                        archived: false,
                        search,
                    })
                    breakpoint()
                    return response.results
                },
            },
        ],
        // A trigger can point at any survey, including one far outside the first page — fetch it by
        // id so an already-configured trigger renders its survey instead of looking unset.
        // A null entry means the fetch resolved but the survey is gone.
        selectedSurveys: [
            {} as Record<string, Survey | null>,
            {
                loadSurveyById: async ({ id }) => {
                    if (id in values.selectedSurveys) {
                        return values.selectedSurveys
                    }
                    try {
                        const survey = await api.surveys.get(id)
                        return { ...values.selectedSurveys, [id]: survey }
                    } catch {
                        return { ...values.selectedSurveys, [id]: null }
                    }
                },
            },
        ],
        responseCounts: [
            {} as Record<string, number>,
            {
                loadResponseCounts: async () => {
                    const surveyIds = Object.keys(values.surveysById).join(',')
                    if (!surveyIds) {
                        return {}
                    }
                    return await api.surveys.getResponsesCount(surveyIds)
                },
            },
        ],
    })),
    reducers({
        searchTerm: [
            '' as string,
            {
                setSearchTerm: (_, { searchTerm }) => searchTerm,
            },
        ],
        allSurveys: [
            [] as Survey[],
            {
                loadSurveysSuccess: (_, { surveys }) => surveys,
                loadMoreSurveysSuccess: (state, { moreSurveys }) => [...state, ...moreSurveys],
            },
        ],
        hasMoreSurveys: [
            true,
            {
                loadSurveysSuccess: (_, { surveys }) => surveys.length >= SURVEYS_PAGE_SIZE,
                loadMoreSurveysSuccess: (_, { moreSurveys }) => moreSurveys.length >= SURVEYS_PAGE_SIZE,
            },
        ],
    }),
    selectors({
        filteredSurveys: [
            (s) => [s.allSurveys, s.searchedSurveys, s.searchTerm],
            (allSurveys: Survey[], searchedSurveys: Survey[], searchTerm: string): Survey[] =>
                searchTerm ? searchedSurveys : allSurveys,
        ],
        surveysById: [
            (s) => [s.allSurveys, s.searchedSurveys, s.selectedSurveys],
            (
                allSurveys: Survey[],
                searchedSurveys: Survey[],
                selectedSurveys: Record<string, Survey | null>
            ): Record<string, Survey> => {
                const byId: Record<string, Survey> = {}
                for (const survey of [...allSurveys, ...searchedSurveys]) {
                    byId[survey.id] = survey
                }
                for (const survey of Object.values(selectedSurveys)) {
                    if (survey) {
                        byId[survey.id] = survey
                    }
                }
                return byId
            },
        ],
    }),
    afterMount(({ actions, props }) => {
        actions.loadSurveys()
        if (props.selectedSurveyId) {
            actions.loadSurveyById(props.selectedSurveyId)
        }
    }),
    propsChanged(({ actions, props }, oldProps) => {
        if (props.selectedSurveyId && props.selectedSurveyId !== oldProps.selectedSurveyId) {
            actions.loadSurveyById(props.selectedSurveyId)
        }
    }),
    listeners(({ actions, values }) => ({
        setSearchTerm: () => {
            actions.searchSurveys(values.searchTerm)
        },
        loadSurveysSuccess: () => {
            actions.loadResponseCounts()
        },
        loadMoreSurveysSuccess: () => {
            actions.loadResponseCounts()
        },
        searchSurveysSuccess: () => {
            actions.loadResponseCounts()
        },
        loadSurveyByIdSuccess: () => {
            actions.loadResponseCounts()
        },
        loadSurveysFailure: ({ error }) => {
            lemonToast.error('Failed to load surveys: ' + error)
        },
        loadMoreSurveysFailure: ({ error }) => {
            lemonToast.error('Failed to load more surveys: ' + error)
        },
        searchSurveysFailure: ({ error }) => {
            lemonToast.error('Failed to search surveys: ' + error)
        },
        loadResponseCountsFailure: ({ error }) => {
            lemonToast.error('Failed to load response counts: ' + error)
        },
    })),
])
