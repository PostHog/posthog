import { MakeLogicType, afterMount, connect, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { projectLogic } from 'scenes/projectLogic'

import { hogFlowsInboxReportAccessRetrieve } from 'products/workflows/frontend/generated/api'
import type { InboxReportAccessApi } from 'products/workflows/frontend/generated/api.schemas'

const INBOX_REPORT_ACCESS_DISABLED_REASON = 'You need viewer access to Tasks to use Inbox reports in workflows.'
const INBOX_REPORT_ACCESS_CHECKING_REASON = 'Checking your access to Tasks...'
const INBOX_REPORT_ACCESS_CHECK_FAILED_REASON = "Couldn't check your access to Tasks. Reopen the trigger to try again."

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface inboxReportAccessLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentProjectId: number | null // projectLogic
    inboxReportAccess: InboxReportAccessApi | null
    inboxReportAccessCheckFailed: boolean
    inboxReportAccessLoading: boolean
    inboxReportTriggerDisabledReason: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface inboxReportAccessLogicActions {
    loadInboxReportAccess: () => any
    loadInboxReportAccessFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadInboxReportAccessSuccess: (
        inboxReportAccess: InboxReportAccessApi | null,
        payload?: any
    ) => {
        inboxReportAccess: InboxReportAccessApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface inboxReportAccessLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        inboxReportTriggerDisabledReason: (
            inboxReportAccess: InboxReportAccessApi | null,
            inboxReportAccessCheckFailed: any
        ) => string | null
    }
}

export type inboxReportAccessLogicType = MakeLogicType<
    inboxReportAccessLogicValues,
    inboxReportAccessLogicActions,
    Record<string, any>,
    inboxReportAccessLogicMeta
>

export const inboxReportAccessLogic = kea<inboxReportAccessLogicType>([
    path([
        'products',
        'workflows',
        'frontend',
        'Workflows',
        'hogflows',
        'registry',
        'triggers',
        'inboxReportAccessLogic',
    ]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']],
    })),
    loaders(({ values }) => ({
        inboxReportAccess: [
            null as InboxReportAccessApi | null,
            {
                loadInboxReportAccess: async () => {
                    if (!values.currentProjectId) {
                        return null
                    }
                    return await hogFlowsInboxReportAccessRetrieve(String(values.currentProjectId))
                },
            },
        ],
    })),
    reducers({
        inboxReportAccessCheckFailed: [
            false,
            {
                loadInboxReportAccess: () => false,
                loadInboxReportAccessFailure: () => true,
            },
        ],
    }),
    selectors({
        inboxReportTriggerDisabledReason: [
            (s) => [s.inboxReportAccess, s.inboxReportAccessCheckFailed],
            (access: InboxReportAccessApi | null, checkFailed: boolean): string | null => {
                if (checkFailed) {
                    return INBOX_REPORT_ACCESS_CHECK_FAILED_REASON
                }
                if (access === null) {
                    return INBOX_REPORT_ACCESS_CHECKING_REASON
                }
                return access.can_use_inbox_reports ? null : INBOX_REPORT_ACCESS_DISABLED_REASON
            },
        ],
    }),
    afterMount(({ actions, values }) => {
        if (values.featureFlags[FEATURE_FLAGS.WORKFLOW_INBOX_REPORT_TRIGGER]) {
            actions.loadInboxReportAccess()
        }
    }),
])
