import { MakeLogicType, actions, kea, key, listeners, path, props, reducers } from 'kea'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { ApiConfig } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { urls } from 'scenes/urls'

import { hogFlowsConvertToBroadcast } from 'products/workflows/frontend/generated/api'

import { canEditInWizard, isBroadcastShaped } from '../Broadcasts/broadcastsLogic'
import { HogFlow } from './hogflows/types'

/** Mirrors is_convertible_to_broadcast on the server, which still checks on the move. */
export function canMoveToBroadcasts(workflow: HogFlow | null): boolean {
    return (
        !!workflow &&
        !workflow.origin_product &&
        workflow.status !== 'archived' &&
        workflow.exit_condition === 'exit_only_at_end' &&
        !workflow.draft &&
        isBroadcastShaped(workflow.actions) &&
        canEditInWizard(workflow.actions, workflow.edges)
    )
}

export interface WorkflowBroadcastMoveLogicProps {
    id: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowBroadcastMoveLogicValues {
    moving: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowBroadcastMoveLogicActions {
    moveToBroadcasts: () => {
        value: true
    }
    moveToBroadcastsFailure: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowBroadcastMoveLogicMeta {
    key: string
}

export type workflowBroadcastMoveLogicType = MakeLogicType<
    workflowBroadcastMoveLogicValues,
    workflowBroadcastMoveLogicActions,
    WorkflowBroadcastMoveLogicProps,
    workflowBroadcastMoveLogicMeta
>

export const workflowBroadcastMoveLogic = kea<workflowBroadcastMoveLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'workflowBroadcastMoveLogic', key]),
    props({} as WorkflowBroadcastMoveLogicProps),
    key((props) => props.id),
    actions({
        moveToBroadcasts: true,
        moveToBroadcastsFailure: true,
    }),
    reducers({
        moving: [
            false,
            {
                moveToBroadcasts: () => true,
                moveToBroadcastsFailure: () => false,
            },
        ],
    }),
    listeners(({ actions, props }) => ({
        moveToBroadcasts: async () => {
            try {
                await hogFlowsConvertToBroadcast(String(ApiConfig.getCurrentTeamId()), props.id)
            } catch {
                posthog.capture('workflow broadcast move failed', { workflow_id: props.id })
                lemonToast.error("Couldn't move this workflow to broadcasts. Reload the page and try again.")
                actions.moveToBroadcastsFailure()
                return
            }
            posthog.capture('workflow broadcast move completed', { workflow_id: props.id })
            lemonToast.success('Moved to broadcasts')
            router.actions.push(urls.broadcast(props.id))
        },
    })),
])
