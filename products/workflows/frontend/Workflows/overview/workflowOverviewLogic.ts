export const workflowOverviewLogic = kea<workflowOverviewLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'overview', 'workflowOverviewLogic']),
    props({} as WorkflowOverviewLogicProps),
    key(({ logicKey }: WorkflowOverviewLogicProps) => logicKey),
    connect((props: WorkflowOverviewLogicProps) => ({
        values: [
            workflowLogic,
            ['originalWorkflow'],
            appMetricsLogic({ logicKey: props.logicKey }),
            [
                'params',
                'currentTeam',
                'getDateRangeAbsolute',
                'appMetricsTrends',
                'appMetricsTrendsLoading',
                'appMetricsTrendsPreviousPeriodLoading',
            ],
        ],
        actions: [
            appMetricsLogic({ logicKey: props.logicKey }),
            [
                'setParams',
                'loadAppMetricsTrends',
                'loadAppMetricsTrendsPreviousPeriod',
                'loadAppMetricsTrendsSuccess',
                'loadAppMetricsTrendsFailure',
                'loadAppMetricsTrendsPreviousPeriodSuccess',
                'loadAppMetricsTrendsPreviousPeriodFailure',
            ],
        ],
    })),
    actions({
        retry: true,
    }),
    reducers(({ props }) => {
        // WorkflowOverview builds this appMetricsLogic with its full props before it builds this logic.
        const previousRun = props.previousRunLogicKey
            ? appMetricsLogic({ logicKey: props.previousRunLogicKey }).actionTypes
            : null
        return {
            trendsFailed: [
                false,
                {
                    loadAppMetricsTrendsFailure: () => true,
                    loadAppMetricsTrendsSuccess: () => false,
                },
            ],
            previousPeriodFailed: [
                false,
                {
                    loadAppMetricsTrendsPreviousPeriodFailure: () => true,
                    loadAppMetricsTrendsPreviousPeriodSuccess: () => false,
                },
            ],
            stepTotalsFailed: [
                false,
                {
                    loadStepTotalsFailure: () => true,
                    loadStepTotalsSuccess: () => false,
                },
            ],
            healthTotalsFailed: [
                false,
                {
                    loadHealthTotalsFailure: () => true,
                    loadHealthTotalsSuccess: () => false,
                },
            ],
            previousRunFailed: [
                false,
                previousRun
                    ? {
                          [previousRun.loadAppMetricsTrendsFailure]: () => true,
                          [previousRun.loadAppMetricsTrendsSuccess]: () => false,
                      }
                    : {},
            ],
            previousRunLoading: [
                false,
                previousRun
                    ? {
                          [previousRun.loadAppMetricsTrends]: () => true,
                          [previousRun.loadAppMetricsTrendsFailure]: () => false,
                          [previousRun.loadAppMetricsTrendsSuccess]: () => false,
                      }
                    : {},
            ],
        }
    }),
    loaders(({ props, values }) => ({
        stepTotals: [
            null as Record<string, Partial<Record<StepMetric, number>>> | null,
            {
                loadStepTotals: async (_, breakpoint) => {
                    await breakpoint(10)
                    const dateRange = values.getDateRangeAbsolute()
                    const request: AppMetricsTotalsRequest = {
                        appSource: 'hog_flow',
                        // A batch run records its metrics under the run's id, which the overview passes in as appSourceId.
                        appSourceId: values.params.appSourceId ?? props.id,
                        breakdownBy: ['instance_id', 'metric_name'],
                        metricName: [...STEP_METRICS],
                        limit: STEP_TOTALS_LIMIT,
                        dateFrom: dateRange.dateFrom.toISOString(),
                        dateTo: dateRange.dateTo.toISOString(),
                    }
                    const response = await loadAppMetricsTotals(request, values.currentTeam?.timezone ?? 'UTC')
                    await breakpoint(10)
                    // Step ids come from the workflow author, so a key like "__proto__" must not reach the prototype.
                    const byAction: Record<string, Partial<Record<StepMetric, number>>> = Object.create(null)
                    Object.values(response).forEach(({ total, breakdowns }) => {
                        const [instanceId, metricName] = breakdowns
                        if (!instanceId) {
                            return
                        }
                        byAction[instanceId] = byAction[instanceId] ?? Object.create(null)
                        byAction[instanceId][metricName as StepMetric] =
                            (byAction[instanceId][metricName as StepMetric] ?? 0) + total
                    })
                    return byAction
                },
            },
        ],
        healthTotals: [
            null as Partial<Record<HealthMetric, number>> | null,
            {
                loadHealthTotals: async (_, breakpoint) => {
                    await breakpoint(10)
                    const dateRange = values.getDateRangeAbsolute()
                    const request: AppMetricsTotalsRequest = {
                        appSource: 'hog_flow',
                        appSourceId: values.params.appSourceId ?? props.id,
                        breakdownBy: ['metric_name'],
                        metricName: [...HEALTH_METRICS],
                        dateFrom: dateRange.dateFrom.toISOString(),
                        dateTo: dateRange.dateTo.toISOString(),
                    }
                    const response = await loadAppMetricsTotals(request, values.currentTeam?.timezone ?? 'UTC')
                    await breakpoint(10)
                    const totals: Partial<Record<HealthMetric, number>> = {}
                    Object.values(response).forEach(({ total, breakdowns }) => {
                        const metricName = breakdowns[0] as HealthMetric
                        totals[metricName] = (totals[metricName] ?? 0) + total
                    })
                    return totals
                },
            },
        ],
        inFlight: [
            null as HogFlowInFlightApi | null,
            {
                loadInFlight: async () => {
                    return await hogFlowsInFlightRetrieve(String(ApiConfig.getCurrentTeamId()), props.id)
                },
            },
        ],
    })),
    selectors({
        orderedSteps: [
            (s) => [s.originalWorkflow],
            (workflow: HogFlow | null): HogFlowAction[] =>
                workflow
                    ? getOrderedActions(workflow.actions, workflow.edges)
                          .filter((a) => a.type !== 'trigger')
                          // A branch's timeout path can reach the exit before the main path is walked.
                          .sort((a, b) => Number(a.type === 'exit') - Number(b.type === 'exit'))
                    : [],
        ],
        stepReach: [
            (s) => [
                s.orderedSteps,
                s.stepTotals,
                s.inFlight,
                s.params,
                (_, props: WorkflowOverviewLogicProps): string => props.id,
            ],
            (
                steps: HogFlowAction[],
                stepTotals: Record<string, Partial<Record<StepMetric, number>>> | null,
                inFlight: HogFlowInFlightApi | null,
                params: Partial<AppMetricsCommonParams>,
                id: string
            ): StepReach[] | null =>
                stepTotals
                    ? steps.map((action) => {
                          const totals = stepTotals[action.id] ?? {}
                          const failed = totals.failed ?? 0
                          const isBatchRun = !!params.appSourceId && params.appSourceId !== id
                          const waiting = params.dateTo || isBatchRun ? 0 : (inFlight?.by_action?.[action.id] ?? 0)
                          // A step that continues on error records `succeeded` as well as `failed`. The current
                          // on_error setting is applied to the whole range, so a change to it inside the range skews this.
                          const abortedRuns = action.on_error === 'abort' ? failed : 0
                          return {
                              action,
                              reached: (totals.succeeded ?? 0) + (totals.filtered ?? 0) + abortedRuns,
                              failed,
                              waiting,
                          }
                      })
                    : null,
        ],
        // Counts every step with metrics in the range, including steps since removed from the workflow.
        retrying: [
            (s) => [
                s.appMetricsTrendsLoading,
                s.appMetricsTrendsPreviousPeriodLoading,
                s.previousRunLoading,
                s.stepTotalsLoading,
                s.healthTotalsLoading,
            ],
            (
                trendsLoading: boolean,
                previousPeriodLoading: boolean,
                previousRunLoading: boolean,
                stepTotalsLoading: boolean,
                healthTotalsLoading: boolean
            ): boolean =>
                trendsLoading ||
                previousPeriodLoading ||
                previousRunLoading ||
                stepTotalsLoading ||
                healthTotalsLoading,
        ],
        failedRuns: [
            (s) => [s.stepTotals],
            (stepTotals: Record<string, Partial<Record<StepMetric, number>>> | null): number | null =>
                stepTotals ? Object.values(stepTotals).reduce((sum, totals) => sum + (totals.failed ?? 0), 0) : null,
        ],
        inFlightSteps: [
            (s) => [s.orderedSteps, s.inFlight],
            (steps: HogFlowAction[], inFlight: HogFlowInFlightApi | null): InFlightStep[] => {
                const byAction = inFlight?.by_action ?? {}
                return steps
                    .map((action) => ({ action, count: byAction[action.id] ?? 0 }))
                    .filter((step) => step.count > 0)
                    .sort((a, b) => b.count - a.count)
            },
        ],
    }),
    listeners(({ actions, values, props }) => ({
        setParams: () => {
            actions.loadStepTotals({})
            actions.loadHealthTotals({})
            // appMetricsLogic only reloads its trends on a range change once a load has finished.
            if (!values.appMetricsTrends) {
                actions.loadAppMetricsTrends()
                actions.loadAppMetricsTrendsPreviousPeriod()
            }
        },
        retry: () => {
            actions.loadAppMetricsTrends()
            actions.loadAppMetricsTrendsPreviousPeriod()
            actions.loadStepTotals({})
            actions.loadHealthTotals({})
            actions.loadInFlight()
            if (props.previousRunLogicKey) {
                appMetricsLogic.findMounted({ logicKey: props.previousRunLogicKey })?.actions.loadAppMetricsTrends()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadStepTotals({})
        actions.loadHealthTotals({})
        actions.loadInFlight()
    }),
])
