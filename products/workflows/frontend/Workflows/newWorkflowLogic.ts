export type newWorkflowLogicType = MakeLogicType<
    newWorkflowLogicValues,
    newWorkflowLogicActions,
    Record<string, any>,
    newWorkflowLogicMeta
>

export const newWorkflowLogic = kea<newWorkflowLogicType>([
    path(['products', 'workflows', 'frontend', 'newWorkflowLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            sceneAgentPanelLogic,
            ['sceneIntegrationEnabled'],
            router,
            ['searchParams', 'location'],
        ],
    })),
    actions({
        startNewWorkflow: true,
        showNewWorkflowModal: true,
        hideNewWorkflowModal: true,
        openEditorFromAiComposer: true,
        createWorkflowFromTemplate: (template: HogFlowTemplate) => ({ template }),
        createEmptyWorkflow: true,
    }),
    reducers({
        newWorkflowModalVisible: [
            false,
            {
                showNewWorkflowModal: () => true,
                hideNewWorkflowModal: () => false,
            },
        ],
    }),
    selectors({
        // Same gate as the scene integration. Only the `test` variant, or a plain boolean rollout, qualifies.
        aiFirstNewEnabled: [
            (s) => [s.featureFlags, s.sceneIntegrationEnabled],
            (featureFlags: FeatureFlagsSet, sceneIntegrationEnabled: boolean): boolean =>
                sceneIntegrationEnabled && isAiFirstVariant(FEATURE_FLAGS.WORKFLOWS_AI_FIRST_NEW, featureFlags),
        ],
        // The project folder the composer's draft is created in, while the project browser is on.
        composerFolder: [
            (s) => [s.featureFlags, s.location],
            (featureFlags: FeatureFlagsSet, location: { search: string }): string | null =>
                featureFlags[FEATURE_FLAGS.WORKFLOWS_LIST_V2] ? newWorkflowFolder(location.search) : null,
        ],
        // Deep links with a starting point stay on the editor. Checked here so the scene never reads the flag early.
        aiComposerAvailable: [
            (s) => [s.featureFlags, s.sceneIntegrationEnabled, s.searchParams, s.location],
            (
                featureFlags: FeatureFlagsSet,
                sceneIntegrationEnabled: boolean,
                searchParams: Record<string, any>,
                location: { pathname: string }
            ): boolean =>
                aiComposerAvailable(
                    FEATURE_FLAGS.WORKFLOWS_AI_FIRST_NEW,
                    featureFlags,
                    sceneIntegrationEnabled,
                    searchParams,
                    isNewWorkflowRoute(location.pathname) &&
                        !searchParams.templateId &&
                        !searchParams.editTemplateId &&
                        !searchParams[TRIGGER_PREFILL_PARAM]
                ),
        ],
    }),
    listeners(({ actions, values }) => ({
        startNewWorkflow: () => {
            // Exposure is recorded at the click, and only when the composer could answer it.
            if (values.sceneIntegrationEnabled) {
                posthog.getFeatureFlag(FEATURE_FLAGS.WORKFLOWS_AI_FIRST_NEW)
            }
            if (values.aiFirstNewEnabled) {
                return withNewWorkflowFolder(
                    values.searchParams,
                    !!values.featureFlags[FEATURE_FLAGS.WORKFLOWS_LIST_V2],
                    (folderParams) =>
                        router.actions.push(urls.workflowNew(), {
                            ...folderParams,
                            [EDITOR_MODE_PARAM]: AI_COMPOSER_MODE_VALUE,
                        })
                )
            }
            actions.showNewWorkflowModal()
        },
        openEditorFromAiComposer: () => {
            actions.showNewWorkflowModal()
        },
        createWorkflowFromTemplate: ({ template }) =>
            withNewWorkflowFolder(
                values.searchParams,
                !!values.featureFlags[FEATURE_FLAGS.WORKFLOWS_LIST_V2],
                (folderParams) => {
                    actions.hideNewWorkflowModal()
                    router.actions.push(urls.workflowNew(), {
                        ...folderParams,
                        templateId: template.id,
                    })
                }
            ),
        createEmptyWorkflow: () => {
            const editorMode = values.aiFirstNewEnabled ? { [EDITOR_MODE_PARAM]: EDITOR_MODE_VALUE } : {}
            return withNewWorkflowFolder(
                values.searchParams,
                !!values.featureFlags[FEATURE_FLAGS.WORKFLOWS_LIST_V2],
                (folderParams) => {
                    actions.hideNewWorkflowModal()
                    router.actions.push(urls.workflowNew(), { ...folderParams, ...editorMode })
                }
            )
        },
    })),
    urlToAction(({ actions }) => ({
        '/workflows': (_, _searchParams, hashParams) => {
            if ('newWorkflow' in hashParams) {
                actions.showNewWorkflowModal()
            }
        },
        '/workflows/:tab': (_, _searchParams, hashParams) => {
            if ('newWorkflow' in hashParams) {
                actions.showNewWorkflowModal()
            }
        },
    })),
    actionToUrl({
        hideNewWorkflowModal: () => {
            const hashParams = { ...router.values.hashParams }
            delete hashParams['newWorkflow']
            return [router.values.location.pathname, router.values.searchParams, hashParams]
        },
        showNewWorkflowModal: () => {
            const hashParams = { ...router.values.hashParams }
            hashParams['newWorkflow'] = 'modal'
            return [router.values.location.pathname, router.values.searchParams, hashParams]
        },
    }),
])
