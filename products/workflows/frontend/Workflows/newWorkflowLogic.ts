import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { sceneAgentPanelLogic } from 'scenes/max/sceneAgentPanelLogic'
import { urls } from 'scenes/urls'

import type { HogFlowTemplate } from './hogflows/types'
import { TRIGGER_PREFILL_PARAM } from './workflowTriggerPrefill'

// pinned: URL search param - the escape hatch's deep link into the editor
export const EDITOR_MODE_PARAM = 'mode'
export const EDITOR_MODE_VALUE = 'editor'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newWorkflowLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    searchParams: Record<string, any> // router
    sceneIntegrationEnabled: boolean // sceneAgentPanelLogic
    aiComposerAvailable: boolean
    aiFirstNewEnabled: boolean
    newWorkflowModalVisible: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newWorkflowLogicActions {
    createEmptyWorkflow: () => {
        value: true
    }
    createWorkflowFromTemplate: (template: HogFlowTemplate) => {
        template: HogFlowTemplate
    }
    hideNewWorkflowModal: () => {
        value: true
    }
    openEditorFromAiComposer: () => {
        value: true
    }
    showNewWorkflowModal: () => {
        value: true
    }
    startNewWorkflow: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newWorkflowLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        aiFirstNewEnabled: (featureFlags: FeatureFlagsSet, sceneIntegrationEnabled: boolean) => boolean
        aiComposerAvailable: (aiFirstNewEnabled: boolean, searchParams: Record<string, any>) => boolean
    }
}

export type newWorkflowLogicType = MakeLogicType<
    newWorkflowLogicValues,
    newWorkflowLogicActions,
    Record<string, any>,
    newWorkflowLogicMeta
>

export const newWorkflowLogic = kea<newWorkflowLogicType>([
    path(['products', 'workflows', 'frontend', 'newWorkflowLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            sceneAgentPanelLogic,
            ['sceneIntegrationEnabled'],
            router,
            ['searchParams'],
        ],
    })),
    actions({
        startNewWorkflow: true,
        showNewWorkflowModal: true,
        hideNewWorkflowModal: true,
        openEditorFromAiComposer: true,
        createWorkflowFromTemplate: (template: HogFlowTemplate) => ({ template }),
        createEmptyWorkflow: true,
    }),
    reducers({
        newWorkflowModalVisible: [
            false,
            {
                showNewWorkflowModal: () => true,
                hideNewWorkflowModal: () => false,
            },
        ],
    }),
    selectors({
        // The composer is the side panel's runner, so it needs the same gate as the scene integration.
        aiFirstNewEnabled: [
            (s) => [s.featureFlags, s.sceneIntegrationEnabled],
            (featureFlags: FeatureFlagsSet, sceneIntegrationEnabled: boolean): boolean =>
                !!featureFlags[FEATURE_FLAGS.WORKFLOWS_AI_FIRST_NEW] && sceneIntegrationEnabled,
        ],
        // Template, template-edit and trigger-prefill deep links already carry a starting point, and the
        // escape hatch marks its own route, so all of those land in the editor as before.
        aiComposerAvailable: [
            (s) => [s.aiFirstNewEnabled, s.searchParams],
            (aiFirstNewEnabled: boolean, searchParams: Record<string, any>): boolean =>
                aiFirstNewEnabled &&
                !searchParams.templateId &&
                !searchParams.editTemplateId &&
                !searchParams[TRIGGER_PREFILL_PARAM] &&
                searchParams[EDITOR_MODE_PARAM] !== EDITOR_MODE_VALUE,
        ],
    }),
    listeners(({ actions, values }) => ({
        startNewWorkflow: () => {
            if (values.aiFirstNewEnabled) {
                router.actions.push(urls.workflowNew())
            } else {
                actions.showNewWorkflowModal()
            }
        },
        openEditorFromAiComposer: () => {
            posthog.capture('workflow ai composer escape hatch clicked')
            actions.showNewWorkflowModal()
        },
        createWorkflowFromTemplate: ({ template }) => {
            actions.hideNewWorkflowModal()
            router.actions.push(urls.workflowNew(), { templateId: template.id })
        },
        createEmptyWorkflow: () => {
            actions.hideNewWorkflowModal()
            router.actions.push(
                urls.workflowNew(),
                values.aiFirstNewEnabled ? { [EDITOR_MODE_PARAM]: EDITOR_MODE_VALUE } : {}
            )
        },
    })),
    urlToAction(({ actions }) => ({
        '/workflows': (_, _searchParams, hashParams) => {
            if ('newWorkflow' in hashParams) {
                actions.showNewWorkflowModal()
            }
        },
        '/workflows/:tab': (_, _searchParams, hashParams) => {
            if ('newWorkflow' in hashParams) {
                actions.showNewWorkflowModal()
            }
        },
    })),
    actionToUrl({
        hideNewWorkflowModal: () => {
            const hashParams = { ...router.values.hashParams }
            delete hashParams['newWorkflow']
            return [router.values.location.pathname, router.values.searchParams, hashParams]
        },
        showNewWorkflowModal: () => {
            const hashParams = { ...router.values.hashParams }
            hashParams['newWorkflow'] = 'modal'
            return [router.values.location.pathname, router.values.searchParams, hashParams]
        },
    }),
])
