export const workflowProposalsLogic = kea<workflowProposalsLogicType>([
    path(['products', 'workflows', 'frontend', 'Workflows', 'suggestions', 'workflowProposalsLogic']),
    props({} as WorkflowProposalsLogicProps),
    key(({ id }) => id),
    connect(({ id }: WorkflowProposalsLogicProps) => ({
        values: [
            teamLogic,
            ['currentTeamIdStrict'],
            workflowLogic({ id }),
            ['hasStagedDraft', 'hasUnsavedChanges', 'showDraftActions', 'originalWorkflow'],
        ],
    })),
    actions({
        approveProposal: (proposalId: string) => ({ proposalId }),
        confirmApproveProposal: (proposalId: string, expectedDraftUpdatedAt: string | null) => ({
            proposalId,
            expectedDraftUpdatedAt,
        }),
        rejectProposal: (proposalId: string) => ({ proposalId }),
        confirmRejectProposal: (proposalId: string) => ({ proposalId }),
        removeResolvedProposal: (proposalId: string) => ({ proposalId }),
        setResolvingId: (proposalId: string | null, action: 'approve' | 'reject' | null = null) => ({
            proposalId,
            action,
        }),
        loadOutcome: (proposalId: string) => ({ proposalId }),
        setLastSeen: (version: number | null, draftStamp: string | null) => ({ version, draftStamp }),
        setOptimizationUnreadable: (unreadable: boolean) => ({ unreadable }),
        reloadLists: true,
        setOptimizationEnabled: (enabled: boolean) => ({ enabled }),
        setOutcome: (proposalId: string, outcome: WorkflowProposalOutcomeApi) => ({ proposalId, outcome }),
    }),
    reducers({
        // The server has resolved this one. Dropping it here means a reload that fails afterwards
        // cannot leave a resolved suggestion in the queue with live buttons.
        proposalsResponse: {
            removeResolvedProposal: (
                response: PaginatedWorkflowProposalListApi | null,
                { proposalId }: { proposalId: string }
            ): PaginatedWorkflowProposalListApi | null =>
                response
                    ? {
                          ...response,
                          results: (response.results ?? []).filter((proposal) => proposal.id !== proposalId),
                      }
                    : response,
        },
        // A list that rejects leaves its response null with nothing loading, which reads the same as
        // "not asked yet". Without this the panel waits on a request that already failed.
        listsUnreadable: [
            false,
            {
                loadProposalsFailure: () => true,
                loadApprovedFailure: () => true,
                loadAppliedFailure: () => true,
                reloadLists: () => false,
            },
        ],
        resolvingId: [
            null as string | null,
            {
                setResolvingId: (_, { proposalId }) => proposalId,
            },
        ],
        resolvingAction: [
            null as 'approve' | 'reject' | null,
            {
                setResolvingId: (_, { action }) => action,
            },
        ],
        // A failed read must not read as "off".
        optimizationUnreadable: [
            false,
            {
                setOptimizationUnreadable: (_, { unreadable }) => unreadable,
                loadOptimizationSuccess: () => false,
                setOptimizationEnabledSuccess: () => false,
            },
        ],
        lastSeenVersion: [
            null as number | null,
            {
                setLastSeen: (_, { version }) => version,
            },
        ],
        // Discard and restore return an approved suggestion to the queue without moving the version,
        // but both rewrite the draft stamp, so the queue follows that too.
        lastSeenDraftStamp: [
            null as string | null,
            {
                setLastSeen: (_, { draftStamp }) => draftStamp,
            },
        ],
        // Merge each finished request's entry here at reducer time, not inside the request. A request
        // that read prior state to build the merged map would read it stale, so two near-simultaneous
        // loads would drop each other's entry.
        outcomes: [
            {} as Record<string, WorkflowProposalOutcomeApi>,
            {
                setOutcome: (state, { proposalId, outcome }) => ({ ...state, [proposalId]: outcome }),
            },
        ],
    }),
    loaders(({ actions, props, values }) => ({
        approvedResponse: [
            null as PaginatedWorkflowProposalListApi | null,
            {
                loadApproved: async () => {
                    try {
                        return await hogFlowsProposalsList(String(values.currentTeamIdStrict), props.id, {
                            status: 'approved',
                            limit: QUEUE_LIMIT,
                        })
                    } catch (error) {
                        if (error instanceof ApiError && error.status === 404) {
                            return { count: 0, results: [] }
                        }
                        throw error
                    }
                },
            },
        ],
        appliedResponse: [
            null as PaginatedWorkflowProposalListApi | null,
            {
                loadApplied: async () => {
                    try {
                        return await hogFlowsProposalsList(String(values.currentTeamIdStrict), props.id, {
                            status: 'applied',
                            limit: APPLIED_OUTCOME_LIMIT,
                        })
                    } catch (error) {
                        // Only the flag-off 404 is an empty queue; anything else rejects so the loader keeps the last list.
                        if (error instanceof ApiError && error.status === 404) {
                            return { count: 0, results: [] }
                        }
                        throw error
                    }
                },
            },
        ],
        optimization: [
            null as HogFlowOptimizationApi | null,
            {
                loadOptimization: async () => {
                    try {
                        return await hogFlowsOptimizationRetrieve(String(values.currentTeamIdStrict), props.id)
                    } catch (error) {
                        // 404 is the flag being off, which the panel already reads as "nothing here".
                        if (error instanceof ApiError && error.status === 404) {
                            return null
                        }
                        actions.setOptimizationUnreadable(true)
                        throw error
                    }
                },
                setOptimizationEnabled: async ({ enabled }) => {
                    return await hogFlowsOptimizationCreate(String(values.currentTeamIdStrict), props.id, { enabled })
                },
            },
        ],
        proposalsResponse: [
            null as PaginatedWorkflowProposalListApi | null,
            {
                loadProposals: async () => {
                    try {
                        return await hogFlowsProposalsList(String(values.currentTeamIdStrict), props.id, {
                            status: 'suggested',
                            limit: QUEUE_LIMIT,
                        })
                    } catch (error) {
                        // 404 is the flag being off; anything else rejects so the loader keeps the last list.
                        if (error instanceof ApiError && error.status === 404) {
                            return { count: 0, results: [] }
                        }
                        throw error
                    }
                },
            },
        ],
    })),
    selectors({
        approvedProposals: [
            (s) => [s.approvedResponse],
            (response: PaginatedWorkflowProposalListApi | null): WorkflowProposalApi[] => response?.results ?? [],
        ],
        appliedProposals: [
            (s) => [s.appliedResponse],
            (response: PaginatedWorkflowProposalListApi | null): WorkflowProposalApi[] => response?.results ?? [],
        ],
        optimizationEnabled: [
            (s) => [s.optimization],
            (optimization: HogFlowOptimizationApi | null): boolean => !!optimization?.enabled,
        ],
        pendingProposals: [
            (s) => [s.proposalsResponse],
            (response: PaginatedWorkflowProposalListApi | null): WorkflowProposalApi[] => response?.results ?? [],
        ],
        approveDisabledReason: [
            (s) => [s.hasUnsavedChanges, s.showDraftActions],
            (hasUnsavedChanges: boolean, showDraftActions: boolean): string | undefined => {
                // Approving stages the suggestion server-side and reloads the workflow, which drops
                // whatever the form still holds — the same trade discardDisabledReason guards.
                if (hasUnsavedChanges) {
                    return 'Save your changes first'
                }
                // Without the publish and discard controls the staged draft would have no way out.
                if (!showDraftActions) {
                    return 'Only a live workflow can stage a suggestion as a draft'
                }
                return undefined
            },
        ],
    }),
    listeners(({ actions, props, values }) => ({
        reloadLists: () => {
            actions.loadProposals()
            actions.loadApproved()
            actions.loadApplied()
        },
        approveProposal: ({ proposalId }) => {
            if (values.resolvingId !== null || values.approveDisabledReason) {
                return
            }
            // The stamp of the draft this confirmation is about. Approve sends it as a fence, so a
            // draft staged or edited after this dialog opened returns 409 instead of being clobbered.
            const expectedDraftUpdatedAt = values.originalWorkflow?.draft_updated_at ?? null
            LemonDialog.open({
                title: 'Approve this suggestion?',
                description: values.hasStagedDraft
                    ? 'This replaces your current staged draft with the suggested change. The live workflow keeps running until you publish.'
                    : 'This opens the suggested change on the canvas as a draft. The live workflow keeps running until you publish.',
                primaryButton: {
                    children: 'Approve as draft',
                    onClick: () => actions.confirmApproveProposal(proposalId, expectedDraftUpdatedAt),
                },
                secondaryButton: {
                    children: 'Cancel',
                },
            })
        },
        confirmApproveProposal: async ({ proposalId, expectedDraftUpdatedAt }) => {
            if (values.resolvingId !== null) {
                return
            }
            // The form can go dirty while the dialog is open, so the reason is checked again here.
            if (values.approveDisabledReason) {
                lemonToast.error(values.approveDisabledReason)
                return
            }
            actions.setResolvingId(proposalId, 'approve')
            try {
                await hogFlowsProposalsApproveCreate(String(values.currentTeamIdStrict), props.id, proposalId, {
                    // With no stamp to fence against, overwrite would wave through a draft staged
                    // since this dialog opened; false makes the server answer 409 instead.
                    overwrite: expectedDraftUpdatedAt !== null,
                    expected_draft_updated_at: expectedDraftUpdatedAt,
                })
                lemonToast.success('Suggestion staged as a draft. Publish it to go live.')
                actions.removeResolvedProposal(proposalId)
                workflowLogic({ id: props.id }).actions.loadWorkflow()
                actions.loadProposals()
                actions.loadApproved()
            } catch (error) {
                if (error instanceof ApiError && error.status === 409) {
                    if (error.code === 'proposal_already_resolved') {
                        lemonToast.info('This suggestion was already resolved.')
                        actions.removeResolvedProposal(proposalId)
                    } else {
                        lemonToast.error(
                            error.code === 'proposal_out_of_date' && error.detail
                                ? error.detail
                                : 'The staged draft changed while you were confirming. Review it and try again.'
                        )
                    }
                    workflowLogic({ id: props.id }).actions.loadWorkflow()
                    actions.loadProposals()
                } else {
                    lemonToast.error('Could not approve this suggestion. Please try again.')
                }
            } finally {
                actions.setResolvingId(null)
            }
        },
        rejectProposal: ({ proposalId }) => {
            if (values.resolvingId !== null) {
                return
            }
            LemonDialog.open({
                title: 'Reject this suggestion?',
                description: 'It stays in the workflow history as rejected. Nothing changes on the workflow.',
                primaryButton: {
                    children: 'Reject',
                    status: 'danger',
                    onClick: () => actions.confirmRejectProposal(proposalId),
                },
                secondaryButton: {
                    children: 'Cancel',
                },
            })
        },
        confirmRejectProposal: async ({ proposalId }) => {
            if (values.resolvingId !== null) {
                return
            }
            actions.setResolvingId(proposalId, 'reject')
            try {
                await hogFlowsProposalsRejectCreate(String(values.currentTeamIdStrict), props.id, proposalId, {})
                lemonToast.success('Suggestion rejected')
                actions.removeResolvedProposal(proposalId)
                actions.loadProposals()
            } catch (error) {
                if (error instanceof ApiError && error.code === 'proposal_already_resolved') {
                    // Already resolved elsewhere, so "try again" would point at a button that cannot work.
                    lemonToast.info('This suggestion was already resolved.')
                    actions.removeResolvedProposal(proposalId)
                    actions.loadProposals()
                } else {
                    lemonToast.error('Could not reject this suggestion. Please try again.')
                }
            } finally {
                actions.setResolvingId(null)
            }
        },
    })),
    listeners(({ actions, props, values }) => ({
        loadAppliedSuccess: () => {
            for (const proposal of values.appliedProposals) {
                if (!values.outcomes[proposal.id]) {
                    actions.loadOutcome(proposal.id)
                }
            }
        },
        loadOutcome: async ({ proposalId }) => {
            try {
                const outcome = await hogFlowsProposalsOutcomeRetrieve(
                    String(values.currentTeamIdStrict),
                    props.id,
                    proposalId
                )
                actions.setOutcome(proposalId, outcome)
            } catch {}
        },
    })),
    listeners(({ actions, values, props }) => ({
        // Publish, discard and restore happen outside this panel; the version and the draft stamp cover all three.
        [workflowLogic({ id: props.id }).actionTypes.loadWorkflowSuccess]: () => {
            const version = values.originalWorkflow?.version ?? null
            const draftStamp = values.originalWorkflow?.draft_updated_at ?? null
            if (version === null || (version === values.lastSeenVersion && draftStamp === values.lastSeenDraftStamp)) {
                return
            }
            actions.setLastSeen(version, draftStamp)
            actions.loadProposals()
            actions.loadApproved()
            actions.loadApplied()
        },
    })),
    afterMount(({ actions, values }) => {
        actions.setLastSeen(values.originalWorkflow?.version ?? null, values.originalWorkflow?.draft_updated_at ?? null)
        actions.loadProposals()
        actions.loadApproved()
        actions.loadApplied()
        actions.loadOptimization()
    }),
])
