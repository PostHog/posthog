import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { projectLogic } from 'scenes/projectLogic'

import { workflowEmailLogActivityRetrieve, workflowEmailLogRetrieve } from 'products/messaging/frontend/generated/api'
import type { WorkflowEmailDetailApi } from 'products/messaging/frontend/generated/api.schemas'

import { ActivityPerson, PersonActivity } from '../Transactional/log/emailActivity'
import { fetchActivityPerson, toPersonActivity } from '../Transactional/log/emailActivityQueries'

export interface WorkflowEmailActivityLogicProps {
    invocationId: string
    actionId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowEmailActivityLogicValues {
    currentProjectId: number | null // projectLogic
    activity: PersonActivity | null
    activityFailed: boolean
    activityLoading: boolean
    afterExpanded: boolean
    beforeExpanded: boolean
    email: WorkflowEmailDetailApi | null | undefined
    emailFailed: boolean
    emailLoading: boolean
    person: ActivityPerson | null | undefined
    personFailed: boolean
    personLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowEmailActivityLogicActions {
    loadActivity: () => any
    loadActivityFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadActivitySuccess: (
        activity: PersonActivity | null,
        payload?: any
    ) => {
        activity: PersonActivity | null
        payload?: any
    }
    loadEmail: () => any
    loadEmailFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadEmailSuccess: (
        email: WorkflowEmailDetailApi | null,
        payload?: any
    ) => {
        email: WorkflowEmailDetailApi | null
        payload?: any
    }
    loadPerson: (distinctId: string) => string
    loadPersonFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadPersonSuccess: (
        person: ActivityPerson | null,
        payload?: string
    ) => {
        person: ActivityPerson | null
        payload?: string
    }
    showAllAfter: () => {
        value: true
    }
    showAllBefore: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowEmailActivityLogicMeta {
    key: string
}

export type workflowEmailActivityLogicType = MakeLogicType<
    workflowEmailActivityLogicValues,
    workflowEmailActivityLogicActions,
    WorkflowEmailActivityLogicProps,
    workflowEmailActivityLogicMeta
>

export const workflowEmailActivityLogic = kea<workflowEmailActivityLogicType>([
    props({} as WorkflowEmailActivityLogicProps),
    key((props) => `${props.invocationId}/${props.actionId}`),
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'workflowEmailActivityLogic', key]),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        showAllBefore: true,
        showAllAfter: true,
    }),
    reducers({
        beforeExpanded: [false, { showAllBefore: () => true }],
        afterExpanded: [false, { showAllAfter: () => true }],
        emailFailed: [false, { loadEmail: () => false, loadEmailSuccess: () => false, loadEmailFailure: () => true }],
        personFailed: [
            false,
            { loadPerson: () => false, loadPersonSuccess: () => false, loadPersonFailure: () => true },
        ],
        activityFailed: [
            false,
            { loadActivity: () => false, loadActivitySuccess: () => false, loadActivityFailure: () => true },
        ],
    }),
    loaders(({ props, values }) => ({
        // undefined until the first load answers, null when the project has no engagement events for this send.
        email: [
            undefined as WorkflowEmailDetailApi | null | undefined,
            {
                loadEmail: async () => {
                    if (values.currentProjectId === null) {
                        return null
                    }
                    try {
                        return await workflowEmailLogRetrieve(String(values.currentProjectId), props.invocationId, {
                            action_id: props.actionId,
                        })
                    } catch (error: any) {
                        if (error?.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
            },
        ],
        // undefined until the lookup answers, null when no person has the send's distinct ID.
        person: [
            undefined as ActivityPerson | null | undefined,
            {
                loadPerson: async (distinctId: string) => await fetchActivityPerson(distinctId),
            },
        ],
        activity: [
            null as PersonActivity | null,
            {
                loadActivity: async () =>
                    values.currentProjectId === null
                        ? null
                        : toPersonActivity(
                              await workflowEmailLogActivityRetrieve(
                                  String(values.currentProjectId),
                                  props.invocationId,
                                  { action_id: props.actionId }
                              )
                          ),
            },
        ],
    })),
    listeners(({ actions }) => ({
        loadEmailSuccess: ({ email }) => {
            if (email?.distinct_id) {
                actions.loadPerson(email.distinct_id)
                actions.loadActivity()
            }
        },
    })),
    afterMount(({ actions }) => actions.loadEmail()),
])
