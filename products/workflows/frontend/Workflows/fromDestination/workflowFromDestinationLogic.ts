export const workflowFromDestinationLogic: LogicWrapper<workflowFromDestinationLogicType> =
    kea<workflowFromDestinationLogicType>([
        props({} as WorkflowFromDestinationLogicProps),
        key((props) => props.templateId),
        path((key) => [
            'products',
            'workflows',
            'frontend',
            'Workflows',
            'fromDestination',
            'workflowFromDestinationLogic',
            key,
        ]),
        actions({
            setStep: (step: WorkflowFromDestinationStep) => ({ step }),
            goToNextStep: true,
            goToPreviousStep: true,
            submitWizard: true,
            setName: (name: string) => ({ name }),
            setTriggerFilters: (triggerFilters: EventTriggerFilters) => ({ triggerFilters }),
            setInputs: (inputs: Record<string, CyclotronJobInputType>) => ({ inputs }),
            setInput: (inputKey: string, input: CyclotronJobInputType) => ({ inputKey, input }),
            markStarted: (startedAt: number) => ({ startedAt }),
            setShowValidationErrors: (show: boolean) => ({ show }),
            resetWizard: true,
        }),
        loaders(({ props, values }) => ({
            template: [
                null as HogFunctionTemplateType | null,
                {
                    loadTemplate: async () => await api.hogFunctions.getTemplate(props.templateId),
                },
            ],
            createdWorkflow: [
                null as CreatedWorkflowFromDestination | null,
                {
                    createWorkflow: async () => {
                        const { template, name, triggerFilters, inputs } = values
                        if (!template || !triggerFilters || !inputs) {
                            return null
                        }
                        const { workflow, functionActionId } = buildHogFlowFromDestination({
                            template,
                            name: name || template.name,
                            triggerFilters,
                            inputs: sanitizeInputs({ inputs_schema: template.inputs_schema, inputs }),
                        })
                        const created = await api.hogFlows.createHogFlow(workflow)
                        return { workflow: created, functionActionId }
                    },
                },
            ],
        })),
        reducers({
            // The wizard state persists so it survives the full-page OAuth redirect of the connect step.
            currentStep: [
                'trigger' as WorkflowFromDestinationStep,
                { persist: true },
                {
                    setStep: (_, { step }) => step,
                    resetWizard: () => 'trigger',
                },
            ],
            name: [
                null as string | null,
                { persist: true },
                {
                    setName: (_, { name }) => name,
                    resetWizard: () => null,
                },
            ],
            triggerFilters: [
                null as EventTriggerFilters | null,
                { persist: true },
                {
                    setTriggerFilters: (_, { triggerFilters }) => triggerFilters,
                    resetWizard: () => null,
                },
            ],
            inputs: [
                null as Record<string, CyclotronJobInputType> | null,
                { persist: true },
                {
                    setInputs: (_, { inputs }) => inputs,
                    setInput: (state, { inputKey, input }) => ({ ...state, [inputKey]: input }),
                    resetWizard: () => null,
                },
            ],
            startedAt: [
                null as number | null,
                { persist: true },
                {
                    markStarted: (_, { startedAt }) => startedAt,
                    resetWizard: () => null,
                },
            ],
            showValidationErrors: [
                false,
                {
                    setShowValidationErrors: (_, { show }) => show,
                    setStep: () => false,
                    resetWizard: () => false,
                },
            ],
            templateLoadFailed: [
                false,
                {
                    loadTemplate: () => false,
                    loadTemplateFailure: () => true,
                },
            ],
        }),
        selectors({
            integrationInputSchema: [
                (s) => [s.template],
                (template: HogFunctionTemplateType | null): CyclotronJobInputSchemaType | null =>
                    template?.inputs_schema?.find((schema) => schema.type === 'integration') ?? null,
            ],
            steps: [
                (s) => [s.integrationInputSchema],
                (integrationInputSchema: CyclotronJobInputSchemaType | null): WorkflowFromDestinationStep[] =>
                    integrationInputSchema ? ['trigger', 'connect', 'message'] : ['trigger', 'message'],
            ],
            currentStepIndex: [
                (s) => [s.steps, s.currentStep],
                (steps: WorkflowFromDestinationStep[], currentStep: WorkflowFromDestinationStep): number =>
                    Math.max(steps.indexOf(currentStep), 0),
            ],
            isLastStep: [
                (s) => [s.steps, s.currentStepIndex],
                (steps: WorkflowFromDestinationStep[], currentStepIndex: number): boolean =>
                    currentStepIndex === steps.length - 1,
            ],
            // The connect step owns the integration input, so the message step hides it. The schema entry
            // stays in the list because the channel picker looks its integration up by key.
            messageInputsSchema: [
                (s) => [s.template, s.integrationInputSchema],
                (
                    template: HogFunctionTemplateType | null,
                    integrationInputSchema: CyclotronJobInputSchemaType | null
                ): CyclotronJobInputSchemaType[] =>
                    (template?.inputs_schema ?? []).map((schema) =>
                        schema.key === integrationInputSchema?.key ? { ...schema, hidden: true } : schema
                    ),
            ],
            triggerError: [
                (s) => [s.triggerFilters],
                (
                    triggerFilters: {
                        actions?: any[] | undefined
                        events?: any[] | undefined
                        filter_test_accounts?: boolean | undefined
                        properties?: any[] | undefined
                    } | null
                ): string | null => (hasTriggerTarget(triggerFilters) ? null : TRIGGER_TARGET_ERROR),
            ],
            connectError: [
                (s) => [s.integrationInputSchema, s.inputs],
                (
                    integrationInputSchema: CyclotronJobInputSchemaType | null,
                    inputs: Record<
                        string,
                        {
                            bytecode?: any
                            order?: number | undefined
                            secret?: boolean | undefined
                            templating?: 'hog' | 'liquid' | undefined
                            value: any
                        }
                    > | null
                ): string | null => {
                    if (!integrationInputSchema || !isInputMissing(inputs?.[integrationInputSchema.key])) {
                        return null
                    }
                    return `Connect ${getIntegrationNameFromKind(integrationInputSchema.integration ?? '')} to continue.`
                },
            ],
            messageErrors: [
                (s) => [s.messageInputsSchema, s.inputs],
                (
                    messageInputsSchema: CyclotronJobInputSchemaType[],
                    inputs: Record<
                        string,
                        {
                            bytecode?: any
                            order?: number | undefined
                            secret?: boolean | undefined
                            templating?: 'hog' | 'liquid' | undefined
                            value: any
                        }
                    > | null
                ): Record<string, string> => {
                    const errors: Record<string, string> = {}
                    for (const schema of messageInputsSchema) {
                        if (schema.required && !schema.hidden && isInputMissing(inputs?.[schema.key])) {
                            errors[schema.key] = REQUIRED_INPUT_ERROR
                        }
                    }
                    return errors
                },
            ],
            errorsByStep: [
                (s) => [s.triggerError, s.connectError, s.messageErrors],
                (
                    triggerError: string | null,
                    connectError: string | null,
                    messageErrors: Record<string, string>
                ): Partial<Record<WorkflowFromDestinationStep, string[]>> => ({
                    ...(triggerError ? { trigger: [triggerError] } : {}),
                    ...(connectError ? { connect: [connectError] } : {}),
                    ...(Object.keys(messageErrors).length ? { message: Object.values(messageErrors) } : {}),
                }),
            ],
            currentStepError: [
                (s) => [s.errorsByStep, s.currentStep],
                (
                    errorsByStep: Partial<Record<WorkflowFromDestinationStep, string[]>>,
                    currentStep: WorkflowFromDestinationStep
                ): string | null => errorsByStep[currentStep]?.[0] ?? null,
            ],
            // Errors only show for steps the user has reached; submit jumps to a later invalid step first.
            stepErrors: [
                (s) => [s.errorsByStep, s.showValidationErrors, s.steps, s.currentStepIndex],
                (
                    errorsByStep: Partial<Record<WorkflowFromDestinationStep, string[]>>,
                    showValidationErrors: boolean,
                    steps: WorkflowFromDestinationStep[],
                    currentStepIndex: number
                ): Partial<Record<WorkflowFromDestinationStep, string[]>> => {
                    if (!showValidationErrors) {
                        return {}
                    }
                    const reachedSteps = steps.slice(0, currentStepIndex + 1)
                    return Object.fromEntries(
                        Object.entries(errorsByStep).filter(([step]) =>
                            reachedSteps.includes(step as WorkflowFromDestinationStep)
                        )
                    )
                },
            ],
        }),
        listeners(({ actions, values, props, cache }) => ({
            loadTemplateSuccess: ({ template }) => {
                if (!template) {
                    return
                }
                if (values.startedAt === null) {
                    actions.markStarted(Date.now())
                }
                if (values.triggerFilters === null) {
                    actions.setTriggerFilters(seedTriggerFilters(template))
                }
                if (values.inputs === null) {
                    actions.setInputs(templateToConfiguration(template).inputs ?? {})
                }
                if (values.name === null) {
                    actions.setName(`${template.name} notification`)
                }
                const { integration_target, integration_id } = cache.paramsFromUrl ?? {}
                if (integration_target && integration_id) {
                    actions.setInput(integration_target, { value: Number(integration_id) })
                }
            },
            goToNextStep: () => {
                if (values.currentStepError) {
                    actions.setShowValidationErrors(true)
                    return
                }
                const nextStep = values.steps[values.currentStepIndex + 1]
                if (!nextStep) {
                    return
                }
                posthog.capture('workflow_from_destination_step_completed', {
                    template_id: props.templateId,
                    step: values.currentStep,
                })
                actions.setStep(nextStep)
            },
            goToPreviousStep: () => {
                const previousStep = values.steps[values.currentStepIndex - 1]
                if (previousStep) {
                    actions.setStep(previousStep)
                }
            },
            submitWizard: () => {
                const firstInvalidStep = values.steps.find((step) => values.errorsByStep[step])
                if (firstInvalidStep) {
                    actions.setStep(firstInvalidStep)
                    actions.setShowValidationErrors(true)
                    return
                }
                actions.createWorkflow()
            },
            createWorkflowSuccess: ({ createdWorkflow }) => {
                if (!createdWorkflow) {
                    return
                }
                posthog.capture('hog_flow_created_from_destination_template', {
                    workflow_id: createdWorkflow.workflow.id,
                    template_id: props.templateId,
                    has_integration_step: !!values.integrationInputSchema,
                    event_count:
                        (values.triggerFilters?.events?.length ?? 0) + (values.triggerFilters?.actions?.length ?? 0),
                    property_filter_count: values.triggerFilters?.properties?.length ?? 0,
                })
                void addProductIntent({
                    product_type: ProductKey.WORKFLOWS,
                    intent_context: ProductIntentContext.WORKFLOW_CREATED,
                })
                lemonToast.success('Workflow created as a draft. Review it in the editor, then enable it.')
                actions.resetWizard()
                router.actions.push(urls.workflow(createdWorkflow.workflow.id, 'workflow'), {
                    node: createdWorkflow.functionActionId,
                })
            },
            createWorkflowFailure: ({ errorObject }) => {
                const detail = typeof errorObject?.detail === 'string' ? errorObject.detail : null
                lemonToast.error(detail ?? 'Could not create the workflow. Check the settings and try again.')
            },
        })),
        afterMount(({ actions, values, props, cache }) => {
            const { integration_id, integration_target } = router.values.searchParams
            cache.paramsFromUrl = { integration_id, integration_target }
            const returningFromOAuth = !!integration_target

            if (
                !returningFromOAuth &&
                values.startedAt !== null &&
                Date.now() - values.startedAt > WIZARD_STATE_TTL_MS
            ) {
                actions.resetWizard()
            }

            if (returningFromOAuth) {
                const searchParams = { ...router.values.searchParams }
                delete searchParams.integration_id
                delete searchParams.integration_target
                router.actions.replace(router.values.location.pathname, searchParams, router.values.hashParams)
            }

            posthog.capture('workflow_from_destination_wizard_opened', {
                template_id: props.templateId,
                returning_from_oauth: returningFromOAuth,
            })
            actions.loadTemplate()
        }),
    ])
