export const TRIGGER_TARGET_ERROR = 'Pick at least one event or action, or add a property filter.'
const REQUIRED_INPUT_ERROR = 'This field is required.'

function hasTriggerTarget(filters: EventTriggerFilters | null): boolean {
    if (!filters) {
        return false
    }
    return (filters.events?.length ?? 0) + (filters.actions?.length ?? 0) + (filters.properties?.length ?? 0) > 0
}

// Templates can ship placeholder events with an empty id (Mailgun does); those must not count as a
// chosen trigger.
function seedTriggerFilters(template: HogFunctionTemplateType): EventTriggerFilters {
    const filters = (template.filters ?? {}) as EventTriggerFilters
    const seeded: EventTriggerFilters = {}
    const events = (filters.events ?? []).filter((event: { id?: string | number | null }) => !!event.id)
    if (events.length) {
        seeded.events = events
    }
    if (filters.actions?.length) {
        seeded.actions = filters.actions
    }
    if (filters.properties?.length) {
        seeded.properties = filters.properties
    }
    if (filters.filter_test_accounts !== undefined) {
        seeded.filter_test_accounts = filters.filter_test_accounts
    }
    return seeded
}

function isInputMissing(input: CyclotronJobInputType | undefined): boolean {
    const value = input?.value
    return value === undefined || value === null || value === ''
}

