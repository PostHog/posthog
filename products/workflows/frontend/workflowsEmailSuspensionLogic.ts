import { MakeLogicType, afterMount, connect, kea, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { projectLogic } from 'scenes/projectLogic'

import { hogFlowsEmailSendingSuspensionRetrieve } from 'products/workflows/frontend/generated/api'
import type {
    EmailSendingAllowanceApi,
    EmailSendingSuspensionStatusApi,
} from 'products/workflows/frontend/generated/api.schemas'

export interface ReachedEmailSendingCap {
    period: 'hour' | 'day'
    limit: number
}

// The totals count sends in the rolling window. They do not show the worker's token bucket state,
// so a full window means the allowance is spent, not that a send was held back.
export function resolveReachedEmailSendingCap(
    allowance: EmailSendingAllowanceApi | null
): ReachedEmailSendingCap | null {
    // A tier that is only measured never holds a send back, so there is nothing to warn about.
    if (!allowance?.enforced) {
        return null
    }
    // The daily cap is reported first: when both are full, it is the one that delays sends longest.
    if (allowance.emails_per_day > 0 && allowance.emails_sent_last_day >= allowance.emails_per_day) {
        return { period: 'day', limit: allowance.emails_per_day }
    }
    if (allowance.emails_per_hour > 0 && allowance.emails_sent_last_hour >= allowance.emails_per_hour) {
        return { period: 'hour', limit: allowance.emails_per_hour }
    }
    return null
}

