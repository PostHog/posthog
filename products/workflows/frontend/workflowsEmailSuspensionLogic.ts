export type workflowsEmailSuspensionLogicType = MakeLogicType<
    workflowsEmailSuspensionLogicValues,
    workflowsEmailSuspensionLogicActions,
    Record<string, any>,
    workflowsEmailSuspensionLogicMeta
>

export const workflowsEmailSuspensionLogic = kea<workflowsEmailSuspensionLogicType>([
    path(['products', 'workflows', 'frontend', 'workflowsEmailSuspensionLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    loaders(({ values }) => ({
        suspensionStatus: [
            null as EmailSendingSuspensionStatusApi | null,
            {
                loadSuspensionStatus: async () => {
                    if (!values.currentProjectId) {
                        return null
                    }
                    return await hogFlowsEmailSendingSuspensionRetrieve(String(values.currentProjectId))
                },
            },
        ],
    })),
    selectors({
        emailSendingSuspended: [
            (s) => [s.suspensionStatus],
            (status: EmailSendingSuspensionStatusApi | null): boolean => status?.email_sending_suspended ?? false,
        ],
        emailSendingSuspensionReason: [
            (s) => [s.suspensionStatus],
            (status: EmailSendingSuspensionStatusApi | null): string => status?.email_sending_suspension_reason ?? '',
        ],
        // A provider pause drops sends instead of queueing them, so it silences the cap banner the
        // same way the staff suspension does.
        emailSendingProviderSuspended: [
            (s) => [s.suspensionStatus],
            (status: EmailSendingSuspensionStatusApi | null): boolean =>
                status?.email_sending_provider_suspended ?? false,
        ],
        reachedEmailSendingCap: [
            (s) => [s.suspensionStatus],
            (status: EmailSendingSuspensionStatusApi | null): ReachedEmailSendingCap | null =>
                resolveReachedEmailSendingCap(status?.sending_allowance ?? null),
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadSuspensionStatus()
    }),
])
