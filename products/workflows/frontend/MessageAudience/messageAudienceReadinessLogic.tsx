const COHORT_POLL_MS = 3000

export interface MessageAudienceReadinessLogicProps {
    audience: MessageAudience
}

const HAS_EMAIL: AnyPropertyFilter = {
    key: 'email',
    type: PropertyFilterType.Person,
    operator: PropertyOperator.IsSet,
}

function cohortIds(properties: AnyPropertyFilter[]): number[] {
    return [
        ...new Set(
            properties
                .filter(
                    (filter) => filter.type === PropertyFilterType.Cohort && filter.operator !== PropertyOperator.NotIn
                )
                .map((filter) => Number(filter.value))
                .filter((id) => Number.isInteger(id) && id > 0)
        ),
    ]
}

