/**
 * Sizes a "message these people" audience before the person leaves the page they're on, and collects what
 * would stop the email from going out, so the entry point can show the count and warn early.
 */
export const messageAudienceReadinessLogic = kea<messageAudienceReadinessLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'MessageAudience', 'messageAudienceReadinessLogic', key]),
    props({} as MessageAudienceReadinessLogicProps),
    key((props) => `${props.audience.source}:${JSON.stringify(props.audience.properties)}`),
    connect(() => ({
        values: [
            projectLogic,
            ['currentProjectId'],
            integrationsLogic,
            ['integrations'],
            workflowsEmailSuspensionLogic,
            ['emailSendingSuspended'],
        ],
    })),

    actions({
        open: (destination: MessageAudienceDestination) => ({ destination }),
        navigate: (destination: MessageAudienceDestination) => ({ destination }),
        navigateFinished: true,
        loadCohorts: true,
        setCohorts: (cohorts: MessageAudienceCohort[]) => ({ cohorts }),
    }),

    loaders(({ props, values }) => ({
        size: [
            null as MessageAudienceSize | null,
            {
                loadSize: async () => {
                    if (!values.currentProjectId) {
                        return null
                    }
                    const projectId = String(values.currentProjectId)
                    const properties = props.audience.properties
                    // The same email dedupe the launch check uses, so the limit comparison matches it.
                    const [all, withEmail] = await Promise.all([
                        hogFlowsUserBlastRadiusCreate(projectId, { filters: { properties }, dedupe_key: 'email' }),
                        hogFlowsUserBlastRadiusCreate(projectId, {
                            filters: { properties: [...properties, HAS_EMAIL] },
                            dedupe_key: 'email',
                        }),
                    ])
                    return { reach: all.affected, withEmail: withEmail.affected, limit: all.limit }
                },
            },
        ],
    })),

    reducers({
        sizeFailed: [
            false,
            {
                loadSize: () => false,
                loadSizeSuccess: () => false,
                loadSizeFailure: () => true,
            },
        ],
        navigating: [
            false,
            {
                navigate: () => true,
                navigateFinished: () => false,
            },
        ],
        cohorts: [
            [] as MessageAudienceCohort[],
            {
                setCohorts: (_, { cohorts }) => cohorts,
            },
        ],
    }),

    selectors({
        readiness: [
            (s) => [s.size, s.sizeLoading, s.sizeFailed, s.cohorts, s.integrations, s.emailSendingSuspended],
            (
                size: MessageAudienceSize | null,
                sizeLoading: boolean,
                sizeFailed: boolean,
                cohorts: MessageAudienceCohort[],
                integrations: IntegrationType[] | null,
                emailSendingSuspended: boolean
            ): MessageAudienceReadiness =>
                messageAudienceReadiness({
                    size,
                    sizeLoading,
                    sizeFailed,
                    cohorts,
                    integrations,
                    emailSendingSuspended,
                }),
        ],
    }),

    listeners(({ actions, values, props }) => ({
        loadCohorts: async (_, breakpoint) => {
            const ids = cohortIds(props.audience.properties)
            if (!values.currentProjectId || ids.length === 0) {
                return
            }
            const projectId = String(values.currentProjectId)
            const loaded = await Promise.all(
                ids.map(async (id) => {
                    try {
                        return toMessageAudienceCohort(await cohortsRetrieve(projectId, id))
                    } catch {
                        // The send step reports a cohort it can't read, so a failed status check stays quiet here.
                        return null
                    }
                })
            )
            breakpoint()
            const wasPending = values.cohorts.some((cohort) => cohort.pending)
            const cohorts = loaded.filter((cohort): cohort is MessageAudienceCohort => cohort !== null)
            actions.setCohorts(cohorts)
            const pending = cohorts.some((cohort) => cohort.pending)
            if (wasPending && !pending) {
                actions.loadSize()
            }
            if (pending) {
                await breakpoint(COHORT_POLL_MS)
                actions.loadCohorts()
            }
        },
        open: ({ destination }) => {
            captureMessageAudienceClicked(props.audience.source, destination)
            // Only the sender problems apply to a workflow: it sends per person as they qualify, so the
            // audience size and the broadcast limit don't.
            const warnings =
                destination === 'broadcast'
                    ? values.readiness.warnings
                    : [
                          emailSuspensionWarning(values.emailSendingSuspended),
                          emailSenderWarning(values.integrations),
                      ].filter((warning): warning is string => !!warning)
            if (warnings.length === 0) {
                actions.navigate(destination)
                return
            }
            LemonDialog.open({
                title: 'Before you send',
                content: (
                    <ul className="list-disc pl-4 m-0 flex flex-col gap-1" data-attr="message-audience-warnings">
                        {warnings.map((warning) => (
                            <li key={warning}>{warning}</li>
                        ))}
                    </ul>
                ),
                primaryButton: {
                    children: 'Continue',
                    onClick: () => actions.navigate(destination),
                    'data-attr': `message-audience-${props.audience.source}-continue`,
                },
                secondaryButton: warnings.includes(emailSenderWarning(values.integrations) ?? '')
                    ? { children: 'Set up email', onClick: () => router.actions.push(urls.workflows('channels')) }
                    : { children: 'Cancel' },
            })
        },
        navigate: async ({ destination }) => {
            if (destination !== 'broadcast' || !props.audience.sourceRecord || !values.currentProjectId) {
                actions.navigateFinished()
                router.actions.push(messageAudienceUrl(props.audience, destination))
                return
            }
            const check = await checkPreviousRecipients(String(values.currentProjectId), props.audience)
            actions.navigateFinished()
            openBroadcastAfterCheck(props.audience, check)
        },
    })),

    afterMount(({ actions }) => {
        actions.loadSize()
        actions.loadCohorts()
    }),
])
