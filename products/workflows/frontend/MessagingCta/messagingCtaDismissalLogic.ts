import { MakeLogicType, actions, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { dayjs } from 'lib/dayjs'

import { MessagingPlacementKey } from '../../mcp/messagingPlacements'

export const DISMISSAL_DAYS = 90

export interface MessagingCtaDismissalLogicProps {
    viewerId: string
    placement: MessagingPlacementKey
}

function storageKey({ viewerId, placement }: MessagingCtaDismissalLogicProps): string {
    // pinned: localStorage key
    return `messaging-cta-dismissed:${viewerId}:${placement}`
}

// Storage can be full or blocked, so a dismissal also lives here and holds until the page reloads.
const dismissedOnThisPage = new Map<string, string>()

function readDismissedAt(props: MessagingCtaDismissalLogicProps): string | null {
    const onThisPage = dismissedOnThisPage.get(storageKey(props))
    if (onThisPage) {
        return onThisPage
    }
    try {
        return localStorage.getItem(storageKey(props))
    } catch {
        return null
    }
}

function writeDismissedAt(props: MessagingCtaDismissalLogicProps, dismissedAt: string): void {
    dismissedOnThisPage.set(storageKey(props), dismissedAt)
    try {
        localStorage.setItem(storageKey(props), dismissedAt)
    } catch {}
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface messagingCtaDismissalLogicValues {
    dismissedAt: string | null
    isDismissed: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface messagingCtaDismissalLogicActions {
    dismiss: () => {
        dismissedAt: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface messagingCtaDismissalLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        isDismissed: (dismissedAt: string | null) => boolean
    }
}

export type messagingCtaDismissalLogicType = MakeLogicType<
    messagingCtaDismissalLogicValues,
    messagingCtaDismissalLogicActions,
    MessagingCtaDismissalLogicProps,
    messagingCtaDismissalLogicMeta
>

export const messagingCtaDismissalLogic = kea<messagingCtaDismissalLogicType>([
    props({} as MessagingCtaDismissalLogicProps),
    key(({ viewerId, placement }) => `${viewerId}:${placement}`),
    path((key) => ['products', 'workflows', 'frontend', 'MessagingCta', 'messagingCtaDismissalLogic', key]),
    actions({
        dismiss: () => ({ dismissedAt: dayjs().toISOString() }),
    }),
    reducers(({ props }) => ({
        dismissedAt: [
            readDismissedAt(props),
            {
                dismiss: (_, { dismissedAt }) => dismissedAt,
            },
        ],
    })),
    selectors({
        isDismissed: [
            (s) => [s.dismissedAt],
            (dismissedAt: string | null): boolean =>
                dismissedAt !== null && dayjs().diff(dayjs(dismissedAt), 'day', true) < DISMISSAL_DAYS,
        ],
    }),
    listeners(({ props }) => ({
        dismiss: ({ dismissedAt }) => {
            writeDismissedAt(props, dismissedAt)
            // pinned: analytics event name and properties
            posthog.capture('messaging cta dismissed', { placement: props.placement })
        },
    })),
])
