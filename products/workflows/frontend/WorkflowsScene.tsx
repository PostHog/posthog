import { sceneConfigurations } from 'scenes/scenes'
import { Scene, SceneExport } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { SceneContent } from '~/layout/scenes/components/SceneContent'
import { SceneTitleSection } from '~/layout/scenes/components/SceneTitleSection'
import { ProductKey } from '~/queries/schema/schema-general'
import { Breadcrumb } from '~/types'

import { EmailSuspensionBanner } from './EmailSuspensionBanner'
import { workflowsEmptyState } from './emptyState/workflowsEmptyState'
import { MessagingTabActions } from './MessagingTabActions'
import { messagingNavTabs } from './messagingTabs'
import { SendingLimitsBanner } from './SendingLimitsBanner'
import { NewWorkflowButton } from './Workflows/NewWorkflowButton'
import { NewWorkflowModal } from './Workflows/NewWorkflowModal'
import { WorkflowsTable } from './Workflows/WorkflowsTable'

const WORKFLOW_SCENE_TABS = ['workflows', 'library', 'channels', 'opt-outs', 'suppression', 'reputation'] as const
export type WorkflowsSceneTab = (typeof WORKFLOW_SCENE_TABS)[number]

export type WorkflowsSceneProps = {
    tab?: WorkflowsSceneTab
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowsSceneLogicValues {
    breadcrumbs: Breadcrumb[]
    currentTab: WorkflowsSceneTab
    logicProps: any
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowsSceneLogicActions {
    setCurrentTab: (tab: WorkflowsSceneTab) => {
        tab: 'channels' | 'library' | 'opt-outs' | 'reputation' | 'suppression' | 'workflows'
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowsSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        logicProps: (arg: any) => any
        breadcrumbs: (
            currentTab: 'channels' | 'library' | 'opt-outs' | 'reputation' | 'suppression' | 'workflows'
        ) => Breadcrumb[]
    }
}

export type workflowsSceneLogicType = MakeLogicType<
    workflowsSceneLogicValues,
    workflowsSceneLogicActions,
    WorkflowsSceneProps,
    workflowsSceneLogicMeta
>

export const workflowsSceneLogic = kea<workflowsSceneLogicType>([
    props({} as WorkflowsSceneProps),
    path(() => ['scenes', 'workflows', 'workflowsSceneLogic']),
    actions({
        setCurrentTab: (tab: WorkflowsSceneTab) => ({ tab }),
    }),
    reducers(() => ({
        currentTab: [
            'workflows' as WorkflowsSceneTab,
            {
                setCurrentTab: (_, { tab }) => tab,
            },
        ],
    })),
    selectors({
        logicProps: [() => [(_, props) => props], (props) => props],
        breadcrumbs: [
            (s) => [s.currentTab],
            (currentTab: WorkflowsSceneTab): Breadcrumb[] => {
                return [
                    {
                        key: [Scene.Workflows, currentTab],
                        name: capitalizeFirstLetter(currentTab.replaceAll('_', ' ')),
                        iconType: 'workflows',
                    },
                ]
            },
        ],
    }),
    trackedActionToUrl(({ values }) => ({
        setCurrentTab: () => [urls.workflows(values.currentTab)],
    })),
    urlToAction(({ actions, values }) => {
        return {
            [urls.workflows()]: () => {
                if (values.currentTab !== 'workflows') {
                    actions.setCurrentTab('workflows')
                }
            },
            [urls.workflows(':tab' as WorkflowsSceneTab)]: ({ tab }) => {
                let possibleTab: WorkflowsSceneTab = (tab as WorkflowsSceneTab) ?? 'workflows'
                possibleTab = WORKFLOW_SCENE_TABS.includes(possibleTab) ? possibleTab : 'workflows'

                if (possibleTab !== values.currentTab) {
                    actions.setCurrentTab(possibleTab)
                }
            },
        }
    }),
])

export const scene: SceneExport<WorkflowsSceneProps> = {
    component: WorkflowsScene,
    logic: workflowsSceneLogic,
    paramsToProps: ({ params: { tab } }) => ({ tab }),
    productKey: ProductKey.WORKFLOWS,
    emptyState: workflowsEmptyState,
}

export function WorkflowsScene(props: WorkflowsSceneProps = {}): JSX.Element {
    const { currentTab } = useValues(workflowsSceneLogic(props))
    const tabs: LemonTab<WorkflowsSceneTab>[] = [
        {
            label: 'Workflows',
            key: 'workflows',
            content: <WorkflowsTable />,
            link: urls.workflows(),
        },
        ...messagingNavTabs((tab) => urls.workflows(tab)),
    ]

    return (
        <SceneContent className="workflows">
            <SceneTitleSection
                name={sceneConfigurations[Scene.Workflows].name}
                description={sceneConfigurations[Scene.Workflows].description}
                resourceType={{
                    type: sceneConfigurations[Scene.Workflows].iconType || 'default_icon_type',
                }}
                actions={
                    <>
                        {currentTab === 'workflows' && <NewWorkflowButton size="small" />}
                        {currentTab !== 'workflows' && (
                            <MessagingTabActions tab={currentTab} channelsUrl={urls.workflows('channels')} />
                        )}
                    </>
                }
            />
            <EmailSuspensionBanner />
            <SendingLimitsBanner
                sendingAllowanceUrl={currentTab === 'reputation' ? undefined : urls.workflows('reputation')}
            />
            <LemonTabs activeKey={currentTab} tabs={tabs} sceneInset data-attr="workflows-scene-tabs" />
            <NewWorkflowModal />
        </SceneContent>
    )
}
