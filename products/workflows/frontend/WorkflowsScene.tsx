// pinned: URL path segments under /workflows - renaming breaks bookmarks
const WORKFLOW_SCENE_TABS = [
    'workflows',
    'templates',
    'library',
    'channels',
    'opt-outs',
    'suppression',
    'reputation',
] as const
export type WorkflowsSceneTab = (typeof WORKFLOW_SCENE_TABS)[number]

export type WorkflowsSceneProps = {
    tab?: WorkflowsSceneTab
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowsSceneLogicValues {
    breadcrumbs: Breadcrumb[]
    currentTab: WorkflowsSceneTab
    logicProps: any
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowsSceneLogicActions {
    setCurrentTab: (tab: WorkflowsSceneTab) => {
        tab: 'channels' | 'library' | 'opt-outs' | 'reputation' | 'suppression' | 'templates' | 'workflows'
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowsSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        logicProps: (arg: any) => any
        breadcrumbs: (
            currentTab: 'channels' | 'library' | 'opt-outs' | 'reputation' | 'suppression' | 'templates' | 'workflows'
        ) => Breadcrumb[]
    }
}

export type workflowsSceneLogicType = MakeLogicType<
    workflowsSceneLogicValues,
    workflowsSceneLogicActions,
    WorkflowsSceneProps,
    workflowsSceneLogicMeta
>

export const workflowsSceneLogic = kea<workflowsSceneLogicType>([
    props({} as WorkflowsSceneProps),
    path(() => ['scenes', 'workflows', 'workflowsSceneLogic']),
    actions({
        setCurrentTab: (tab: WorkflowsSceneTab) => ({ tab }),
    }),
    reducers(() => ({
        currentTab: [
            'workflows' as WorkflowsSceneTab,
            {
                setCurrentTab: (_, { tab }) => tab,
            },
        ],
    })),
    selectors({
        logicProps: [() => [(_, props) => props], (props) => props],
        breadcrumbs: [
            (s) => [s.currentTab],
            (currentTab: WorkflowsSceneTab): Breadcrumb[] => {
                return [
                    {
                        key: [Scene.Workflows, currentTab],
                        name: capitalizeFirstLetter(currentTab.replaceAll('_', ' ')),
                        iconType: 'workflows',
                    },
                ]
            },
        ],
    }),
    trackedActionToUrl(({ values }) => ({
        setCurrentTab: () => [urls.workflows(values.currentTab)],
    })),
    urlToAction(({ actions, values }) => {
        return {
            [urls.workflows()]: () => {
                if (values.currentTab !== 'workflows') {
                    actions.setCurrentTab('workflows')
                }
            },
            [urls.workflows(':tab' as WorkflowsSceneTab)]: ({ tab }) => {
                let possibleTab: WorkflowsSceneTab = (tab as WorkflowsSceneTab) ?? 'workflows'
                possibleTab = WORKFLOW_SCENE_TABS.includes(possibleTab) ? possibleTab : 'workflows'

                if (possibleTab !== values.currentTab) {
                    actions.setCurrentTab(possibleTab)
                }
            },
        }
    }),
])

export const scene: SceneExport<WorkflowsSceneProps> = {
    component: WorkflowsScene,
    logic: workflowsSceneLogic,
    paramsToProps: ({ params: { tab } }) => ({ tab }),
    productKey: ProductKey.WORKFLOWS,
    emptyState: workflowsEmptyState,
}

type WorkflowsTopTab = 'workflows' | 'templates' | 'messaging-setup'

function topTabFor(tab: WorkflowsSceneTab): WorkflowsTopTab {
    if (tab === 'templates' || tab === 'library') {
        return 'templates'
    }
    return isMessagingSetupTab(tab) ? 'messaging-setup' : 'workflows'
}

export function WorkflowsScene(props: WorkflowsSceneProps = {}): JSX.Element {
    const { currentTab: routeTab } = useValues(workflowsSceneLogic(props))
    const { featureFlags } = useValues(featureFlagLogic)
    const newNavigationEnabled = !!featureFlags[FEATURE_FLAGS.WORKFLOWS_NEW_NAVIGATION]
    // The workflow templates page exists only in the new navigation.
    const currentTab: WorkflowsSceneTab = !newNavigationEnabled && routeTab === 'templates' ? 'workflows' : routeTab
    const { startNewWorkflow } = useActions(newWorkflowLogic)
    const { setTypeFilter } = useActions(workflowTemplatesLogic)
    const { filters } = useValues(workflowsLogic)

    const workflowsTab = {
        label: 'Workflows',
        key: 'workflows' as const,
        content: <WorkflowsTable />,
        link: urls.workflows(),
    }
    const showsNewWorkflowButton = currentTab === 'workflows' || currentTab === 'templates'

    return (
        <SceneContent className="workflows">
            <SceneTitleSection
                name={sceneConfigurations[Scene.Workflows].name}
                description={sceneConfigurations[Scene.Workflows].description}
                resourceType={{
                    type: sceneConfigurations[Scene.Workflows].iconType || 'default_icon_type',
                }}
                actions={
                    <>
                        {showsNewWorkflowButton && (
                            <AccessControlAction
                                resourceType={AccessControlResourceType.Workflow}
                                minAccessLevel={AccessControlLevel.Editor}
                            >
                                <LemonButton
                                    data-attr="new-workflow"
                                    onClick={() => {
                                        void addProductIntent({
                                            product_type: ProductKey.WORKFLOWS,
                                            intent_context: ProductIntentContext.WORKFLOW_CREATED,
                                        })
                                        // Open the template chooser on the type the list shows, so a person on the
                                        // Messaging tab sees messaging templates first.
                                        setTypeFilter(
                                            newNavigationEnabled && currentTab === 'workflows'
                                                ? templateTypeForListType(filters.type)
                                                : 'all'
                                        )
                                        startNewWorkflow()
                                    }}
                                    type="primary"
                                    size="small"
                                >
                                    New workflow
                                </LemonButton>
                            </AccessControlAction>
                        )}
                        {currentTab !== 'workflows' && currentTab !== 'templates' && (
                            <MessagingTabActions tab={currentTab} channelsUrl={urls.workflows('channels')} />
                        )}
                    </>
                }
            />
            <EmailSuspensionBanner />
            {newNavigationEnabled ? (
                <LemonTabs<WorkflowsTopTab>
                    activeKey={topTabFor(currentTab)}
                    tabs={[
                        workflowsTab,
                        {
                            label: 'Templates',
                            key: 'templates',
                            link: urls.workflows('library'),
                            content: <WorkflowsTemplates tab={currentTab === 'templates' ? 'templates' : 'library'} />,
                        },
                        {
                            label: 'Messaging',
                            key: 'messaging-setup',
                            link: urls.workflows('channels'),
                            content: (
                                <MessagingSetup
                                    tab={isMessagingSetupTab(currentTab) ? currentTab : 'channels'}
                                    linkFor={(tab) => urls.workflows(tab)}
                                />
                            ),
                        },
                    ]}
                    sceneInset
                    data-attr="workflows-scene-tabs"
                />
            ) : (
                <LemonTabs
                    activeKey={currentTab}
                    tabs={[workflowsTab, ...messagingNavTabs((tab) => urls.workflows(tab))]}
                    sceneInset
                    data-attr="workflows-scene-tabs"
                />
            )}
            <NewWorkflowModal />
        </SceneContent>
    )
}
