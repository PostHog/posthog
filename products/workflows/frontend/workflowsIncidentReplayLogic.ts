export const workflowsIncidentReplayLogic = kea<workflowsIncidentReplayLogicType>([
    path(['products', 'workflows', 'frontend', 'workflowsIncidentReplayLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        replayWorkflow: (id: string) => ({ id }),
        replayWorkflowSuccess: (id: string) => ({ id }),
        replayWorkflowFailure: (id: string) => ({ id }),
    }),
    loaders(({ values }) => ({
        affectedWorkflows: [
            [] as AffectedWorkflow[],
            {
                loadAffectedWorkflows: async () => {
                    if (!values.currentProjectId) {
                        return []
                    }

                    const totals = await loadAppMetricsTotals(
                        {
                            appSource: 'hog_flow',
                            metricName: 'email_failed',
                            breakdownBy: ['app_source_id'],
                            dateFrom: INCIDENT_WINDOW_START,
                            dateTo: INCIDENT_WINDOW_END,
                            limit: 100,
                        },
                        'UTC'
                    )

                    const affected = Object.values(totals)
                        .map((row) => ({ id: row.breakdowns[0], failedCount: row.total }))
                        .filter((row) => row.id && row.failedCount > 0)

                    if (affected.length === 0) {
                        return []
                    }

                    // Fetch each affected workflow by ID rather than intersecting with the list
                    // endpoint: the list caps at a page size, so in projects with more workflows
                    // than one page the affected ones can fall outside it and silently drop off
                    // the banner. Only a definitive 403 (no access) or 404 (hard-deleted, can't
                    // be replayed) drops a row - the same gates the list applied. A transient
                    // retrieve failure (network, 429, 5xx) keeps the row with fallback fields,
                    // so a blip never hides the recovery path.
                    const projectId = String(values.currentProjectId)
                    const dropped = new Set<string>()
                    const flows = await Promise.all(
                        affected.map(async (row) => {
                            try {
                                return await hogFlowsRetrieve(projectId, row.id)
                            } catch (error) {
                                const status = (error as { status?: number }).status
                                if (status === 403 || status === 404) {
                                    dropped.add(row.id)
                                }
                                return null
                            }
                        })
                    )
                    const flowsById = new Map(
                        flows.filter((flow): flow is HogFlowApi => flow !== null).map((flow) => [flow.id, flow])
                    )
                    const visible = affected.filter((row) => !dropped.has(row.id))

                    if (visible.length === 0) {
                        return []
                    }

                    // App metrics are historical counters, so a fully replayed workflow would sit in
                    // the banner forever, and their counts can't be narrowed to the incident's error.
                    // Count the still-failing invocations that carry the incident message instead -
                    // the same server-side filter the rerun uses - so the displayed number is what a
                    // replay would actually target, it shrinks as a replay drains, and the workflow
                    // drops off at zero. A count that errors falls back to the metric total and keeps
                    // the row (never hide the recovery path on a transient failure).
                    //
                    // No `before`: replay lifecycle rows land in the partition of their own
                    // scheduled_at (replay time), so capping at the window end would hide them and
                    // a replayed invocation would read as failed forever. `after` alone bounds the
                    // partition scan; the failed-status collapse then reflects the true latest state.
                    const remainingCounts = await Promise.all(
                        visible.map(async (row) => {
                            try {
                                const response = await hogFlowsInvocationResultsCountRetrieve(projectId, row.id, {
                                    status: 'failed',
                                    error_message_contains: INCIDENT_ERROR_MESSAGE_PREFIX,
                                    after: INCIDENT_WINDOW_START,
                                })
                                return response.count
                            } catch {
                                return row.failedCount
                            }
                        })
                    )

                    return visible
                        .map((row, index) => {
                            const flow = flowsById.get(row.id)
                            return {
                                id: row.id,
                                name: flow?.name ?? '',
                                failedCount: remainingCounts[index],
                                userAccessLevel: (flow?.user_access_level ?? null) as AccessControlLevel | null,
                            }
                        })
                        .filter((row) => row.failedCount > 0)
                        .sort((a, b) => b.failedCount - a.failedCount)
                },
            },
        ],
    })),
    reducers({
        replayStatusById: [
            {} as Record<string, ReplayStatus>,
            {
                replayWorkflow: (state, { id }) => ({ ...state, [id]: 'pending' }),
                replayWorkflowSuccess: (state, { id }) => ({ ...state, [id]: 'queued' }),
                replayWorkflowFailure: (state, { id }) => {
                    const { [id]: _discarded, ...rest } = state
                    return rest
                },
            },
        ],
    }),
    selectors({
        showBanner: [
            (s) => [s.featureFlags, s.affectedWorkflows],
            (featureFlags: FeatureFlagsSet, affectedWorkflows: AffectedWorkflow[]): boolean =>
                !!featureFlags[FEATURE_FLAGS.WORKFLOWS_INCIDENT_REPLAY] && affectedWorkflows.length > 0,
        ],
    }),
    listeners(({ actions, values }) => ({
        replayWorkflow: async ({ id }) => {
            if (!values.currentProjectId) {
                actions.replayWorkflowFailure(id)
                return
            }
            try {
                await hogFlowsRerunCreate(String(values.currentProjectId), id, {
                    filter: {
                        window_start: INCIDENT_WINDOW_START,
                        window_end: INCIDENT_WINDOW_END,
                        error_message_contains: INCIDENT_ERROR_MESSAGE_PREFIX,
                    },
                })
                actions.replayWorkflowSuccess(id)
                lemonToast.success('Replay queued. Failed sends will be retried shortly.')
            } catch {
                actions.replayWorkflowFailure(id)
                lemonToast.error("Couldn't queue the replay. Try again, and contact support if it keeps happening.")
            }
        },
    })),
    // A subscription instead of afterMount: flags can resolve after the logic mounts, and a
    // one-time mount check would then never load. This fires with the value at mount and again
    // when the flag flips on, so only flagged (affected) teams pay for the lookup query.
    subscriptions(({ actions }) => ({
        featureFlags: (featureFlags: FeatureFlagsSet, oldFeatureFlags: FeatureFlagsSet | undefined) => {
            const isOn = !!featureFlags[FEATURE_FLAGS.WORKFLOWS_INCIDENT_REPLAY]
            const wasOn = !!oldFeatureFlags?.[FEATURE_FLAGS.WORKFLOWS_INCIDENT_REPLAY]
            if (isOn && !wasOn) {
                actions.loadAffectedWorkflows()
            }
        },
    })),
])
