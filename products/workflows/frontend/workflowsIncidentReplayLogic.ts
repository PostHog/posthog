import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { loadAppMetricsTotals } from 'lib/components/AppMetrics/appMetricsLogic'
import { FEATURE_FLAGS } from 'lib/constants'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { featureFlagLogic, type FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { projectLogic } from 'scenes/projectLogic'

import {
    hogFlowsInvocationResultsRetrieve,
    hogFlowsList,
    hogFlowsRerunCreate,
} from 'products/workflows/frontend/generated/api'

// The window of the 2026-08-17 email send incident (UTC), padded around the first and last
// observed failures. Both the affected-workflow lookup and the rerun filter use it, so a
// replay only re-enqueues invocations that failed during the incident.
const INCIDENT_WINDOW_START = '2026-08-17T13:00:00.000Z'
const INCIDENT_WINDOW_END = '2026-08-18T22:00:00.000Z'

// Both messages the regression threw start with this, and no other failure mode does, so the
// rerun skips failures unrelated to the incident (e.g. a genuinely broken integration) even
// inside the window. Matches the pre-fix messages in email.service.ts (resolveFromEmailAddress).
const INCIDENT_ERROR_MESSAGE_PREFIX = 'The custom sender address'

export interface AffectedWorkflow {
    id: string
    name: string
    failedCount: number
}

export type ReplayStatus = 'pending' | 'queued'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowsIncidentReplayLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentProjectId: number | null // projectLogic
    affectedWorkflows: AffectedWorkflow[]
    affectedWorkflowsLoading: boolean
    replayStatusById: Record<string, ReplayStatus>
    showBanner: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowsIncidentReplayLogicActions {
    loadAffectedWorkflows: () => any
    loadAffectedWorkflowsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAffectedWorkflowsSuccess: (
        affectedWorkflows: {
            failedCount: number
            id: string
            name: string
        }[],
        payload?: any
    ) => {
        affectedWorkflows: {
            failedCount: number
            id: string
            name: string
        }[]
        payload?: any
    }
    replayWorkflow: (id: string) => {
        id: string
    }
    replayWorkflowFailure: (id: string) => {
        id: string
    }
    replayWorkflowSuccess: (id: string) => {
        id: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowsIncidentReplayLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        showBanner: (featureFlags: FeatureFlagsSet, affectedWorkflows: AffectedWorkflow[]) => boolean
    }
}

export type workflowsIncidentReplayLogicType = MakeLogicType<
    workflowsIncidentReplayLogicValues,
    workflowsIncidentReplayLogicActions,
    Record<string, any>,
    workflowsIncidentReplayLogicMeta
>

export const workflowsIncidentReplayLogic = kea<workflowsIncidentReplayLogicType>([
    path(['products', 'workflows', 'frontend', 'workflowsIncidentReplayLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        replayWorkflow: (id: string) => ({ id }),
        replayWorkflowSuccess: (id: string) => ({ id }),
        replayWorkflowFailure: (id: string) => ({ id }),
    }),
    loaders(({ values }) => ({
        affectedWorkflows: [
            [] as AffectedWorkflow[],
            {
                loadAffectedWorkflows: async () => {
                    if (!values.currentProjectId) {
                        return []
                    }

                    const totals = await loadAppMetricsTotals(
                        {
                            appSource: 'hog_flow',
                            metricName: 'email_failed',
                            breakdownBy: ['app_source_id'],
                            dateFrom: INCIDENT_WINDOW_START,
                            dateTo: INCIDENT_WINDOW_END,
                            limit: 100,
                        },
                        'UTC'
                    )

                    const affected = Object.values(totals)
                        .map((row) => ({ id: row.breakdowns[0], failedCount: row.total }))
                        .filter((row) => row.id && row.failedCount > 0)

                    if (affected.length === 0) {
                        return []
                    }

                    // App metrics are historical counters, so a fully replayed workflow would sit in
                    // the banner forever. Only keep workflows that still have a failed invocation
                    // carrying the incident's error message - the same rows the rerun would target -
                    // so a workflow drops off once its replay drains, and stays while a >10k replay
                    // still has a leftover. A check that errors keeps its row (never hide the
                    // recovery path on a transient failure).
                    const projectId = String(values.currentProjectId)
                    const needle = INCIDENT_ERROR_MESSAGE_PREFIX.toLowerCase()
                    const stillFailing = await Promise.all(
                        affected.map(async (row) => {
                            try {
                                const invocations = await hogFlowsInvocationResultsRetrieve(projectId, row.id, {
                                    status: 'failed',
                                    after: INCIDENT_WINDOW_START,
                                    before: INCIDENT_WINDOW_END,
                                    limit: 500,
                                })
                                return invocations.some((invocation) =>
                                    invocation.error_message.toLowerCase().includes(needle)
                                )
                            } catch {
                                return true
                            }
                        })
                    )
                    const remaining = affected.filter((_, index) => stillFailing[index])

                    if (remaining.length === 0) {
                        return []
                    }

                    const flows = await hogFlowsList(projectId, { limit: 300 })
                    const namesById = new Map((flows.results ?? []).map((flow) => [flow.id, flow.name]))

                    return remaining
                        .map((row) => ({
                            id: row.id,
                            name: namesById.get(row.id) ?? 'Deleted workflow',
                            failedCount: row.failedCount,
                        }))
                        .sort((a, b) => b.failedCount - a.failedCount)
                },
            },
        ],
    })),
    reducers({
        replayStatusById: [
            {} as Record<string, ReplayStatus>,
            {
                replayWorkflow: (state, { id }) => ({ ...state, [id]: 'pending' }),
                replayWorkflowSuccess: (state, { id }) => ({ ...state, [id]: 'queued' }),
                replayWorkflowFailure: (state, { id }) => {
                    const { [id]: _discarded, ...rest } = state
                    return rest
                },
            },
        ],
    }),
    selectors({
        showBanner: [
            (s) => [s.featureFlags, s.affectedWorkflows],
            (featureFlags: FeatureFlagsSet, affectedWorkflows: AffectedWorkflow[]): boolean =>
                !!featureFlags[FEATURE_FLAGS.WORKFLOWS_INCIDENT_REPLAY] && affectedWorkflows.length > 0,
        ],
    }),
    listeners(({ actions, values }) => ({
        replayWorkflow: async ({ id }) => {
            if (!values.currentProjectId) {
                actions.replayWorkflowFailure(id)
                return
            }
            try {
                await hogFlowsRerunCreate(String(values.currentProjectId), id, {
                    filter: {
                        window_start: INCIDENT_WINDOW_START,
                        window_end: INCIDENT_WINDOW_END,
                        error_message_contains: INCIDENT_ERROR_MESSAGE_PREFIX,
                    },
                })
                actions.replayWorkflowSuccess(id)
                lemonToast.success('Replay queued. Failed sends will be retried shortly.')
            } catch {
                actions.replayWorkflowFailure(id)
                lemonToast.error("Couldn't queue the replay. Try again, and contact support if it keeps happening.")
            }
        },
    })),
    afterMount(({ actions, values }) => {
        // Only flagged (affected) teams pay for the lookup query.
        if (values.featureFlags[FEATURE_FLAGS.WORKFLOWS_INCIDENT_REPLAY]) {
            actions.loadAffectedWorkflows()
        }
    }),
])
