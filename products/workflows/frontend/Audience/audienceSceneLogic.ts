import { MakeLogicType, actions, kea, path, reducers, selectors } from 'kea'
import { urlToAction } from 'kea-router'

import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { Breadcrumb } from '~/types'

// pinned: URL path segments under /audience, renaming breaks bookmarks
export const AUDIENCE_TABS = ['recipients', 'engagement', 'topics', 'suppression'] as const
export type AudienceTab = (typeof AUDIENCE_TABS)[number]

export const AUDIENCE_TAB_LABELS: Record<AudienceTab, string> = {
    recipients: 'Recipients',
    engagement: 'Engagement',
    topics: 'Topics',
    suppression: 'Suppression list',
}

const DEFAULT_AUDIENCE_TAB: AudienceTab = 'recipients'

function isAudienceTab(tab: string | undefined): tab is AudienceTab {
    return (AUDIENCE_TABS as readonly (string | undefined)[]).includes(tab)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceSceneLogicValues {
    breadcrumbs: Breadcrumb[]
    currentTab: AudienceTab
    returnedFromRecipient: boolean
    selectedEmail: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceSceneLogicActions {
    closeRecipient: () => {
        value: true
    }
    openRecipient: (email: string) => {
        email: string
    }
    setCurrentTab: (tab: AudienceTab) => {
        tab: AudienceTab
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        breadcrumbs: (currentTab: AudienceTab) => Breadcrumb[]
    }
}

export type audienceSceneLogicType = MakeLogicType<
    audienceSceneLogicValues,
    audienceSceneLogicActions,
    Record<string, any>,
    audienceSceneLogicMeta
>

export const audienceSceneLogic = kea<audienceSceneLogicType>([
    path(['products', 'workflows', 'frontend', 'Audience', 'audienceSceneLogic']),
    actions({
        setCurrentTab: (tab: AudienceTab) => ({ tab }),
        openRecipient: (email: string) => ({ email }),
        closeRecipient: true,
    }),
    reducers({
        currentTab: [DEFAULT_AUDIENCE_TAB as AudienceTab, { setCurrentTab: (_, { tab }) => tab }],
        // Held in memory only: the URL, breadcrumbs and page title must never carry a recipient's address.
        selectedEmail: [
            null as string | null,
            {
                openRecipient: (_, { email }) => email,
                closeRecipient: () => null,
                setCurrentTab: () => null,
            },
        ],
        returnedFromRecipient: [
            false,
            {
                closeRecipient: () => true,
                openRecipient: () => false,
                setCurrentTab: () => false,
            },
        ],
    }),
    selectors({
        breadcrumbs: [
            (s) => [s.currentTab],
            (currentTab: AudienceTab): Breadcrumb[] => [
                { key: [Scene.Audience, currentTab], name: AUDIENCE_TAB_LABELS[currentTab], iconType: 'cohort' },
            ],
        ],
    }),
    urlToAction(({ actions, values }) => {
        // Paging a table or opening the side panel changes only the search or hash; that must not close a recipient.
        const showTab = (tab: AudienceTab): void => {
            if (tab !== values.currentTab) {
                actions.setCurrentTab(tab)
            }
        }
        return {
            [urls.audience()]: () => showTab(DEFAULT_AUDIENCE_TAB),
            [urls.audience(':tab' as AudienceTab)]: ({ tab }) =>
                showTab(isAudienceTab(tab) ? tab : DEFAULT_AUDIENCE_TAB),
        }
    }),
])
