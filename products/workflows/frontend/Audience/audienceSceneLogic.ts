import { MakeLogicType, actions, kea, path, reducers, selectors } from 'kea'
import { urlToAction } from 'kea-router'

import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { Breadcrumb } from '~/types'

// pinned: URL path segments under /audience, renaming breaks bookmarks
export const AUDIENCE_TABS = ['recipients', 'engagement', 'topics', 'suppression'] as const
export type AudienceTab = (typeof AUDIENCE_TABS)[number]

export const AUDIENCE_TAB_LABELS: Record<AudienceTab, string> = {
    recipients: 'Recipients',
    engagement: 'Engagement',
    topics: 'Topics',
    suppression: 'Suppression list',
}

const DEFAULT_AUDIENCE_TAB: AudienceTab = 'recipients'

function isAudienceTab(tab: string | undefined): tab is AudienceTab {
    return (AUDIENCE_TABS as readonly (string | undefined)[]).includes(tab)
}

function audienceBreadcrumbs(currentTab: AudienceTab, selectedEmail: string | null): Breadcrumb[] {
    const breadcrumbs: Breadcrumb[] = [
        { key: Scene.Audience, name: 'Audience', path: urls.audience(), iconType: 'cohort' },
        {
            key: [Scene.Audience, currentTab],
            name: AUDIENCE_TAB_LABELS[currentTab],
            path: selectedEmail ? urls.audience(currentTab) : undefined,
            iconType: 'cohort',
        },
    ]
    if (selectedEmail) {
        breadcrumbs.push({ key: [Scene.Audience, selectedEmail], name: selectedEmail, iconType: 'cohort' })
    }
    return breadcrumbs
}

const RECIPIENT_PATH_PREFIX = '/audience/recipients/'

/**
 * Reads the address from the still-encoded pathname. The route params are already passed through
 * `decodeURI`, so decoding them again would turn a literal `%2B` in an address into `+`.
 */
function recipientEmailFromPathname(pathname: string): string {
    const encodedEmail = removeProjectIdIfPresent(pathname).slice(RECIPIENT_PATH_PREFIX.length)
    try {
        return decodeURIComponent(encodedEmail)
    } catch {
        return encodedEmail
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceSceneLogicValues {
    breadcrumbs: Breadcrumb[]
    currentTab: AudienceTab
    selectedEmail: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceSceneLogicActions {
    openRecipient: (email: string) => {
        email: string
    }
    setCurrentTab: (tab: AudienceTab) => {
        tab: AudienceTab
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        breadcrumbs: (currentTab: AudienceTab, selectedEmail: string | null) => Breadcrumb[]
    }
}

export type audienceSceneLogicType = MakeLogicType<
    audienceSceneLogicValues,
    audienceSceneLogicActions,
    Record<string, any>,
    audienceSceneLogicMeta
>

export const audienceSceneLogic = kea<audienceSceneLogicType>([
    path(['products', 'workflows', 'frontend', 'Audience', 'audienceSceneLogic']),
    actions({
        setCurrentTab: (tab: AudienceTab) => ({ tab }),
        openRecipient: (email: string) => ({ email }),
    }),
    reducers({
        currentTab: [
            DEFAULT_AUDIENCE_TAB as AudienceTab,
            { setCurrentTab: (_, { tab }) => tab, openRecipient: () => 'recipients' },
        ],
        selectedEmail: [null as string | null, { setCurrentTab: () => null, openRecipient: (_, { email }) => email }],
    }),
    selectors({
        breadcrumbs: [
            (s) => [s.currentTab, s.selectedEmail],
            (currentTab: AudienceTab, selectedEmail: string | null): Breadcrumb[] =>
                audienceBreadcrumbs(currentTab, selectedEmail),
        ],
    }),
    urlToAction(({ actions }) => ({
        [urls.audience()]: () => actions.setCurrentTab(DEFAULT_AUDIENCE_TAB),
        // A wildcard, because a `:email` segment only matches the ASCII characters initKea allows.
        [`${RECIPIENT_PATH_PREFIX}*`]: (_, __, ___, { pathname }) =>
            actions.openRecipient(recipientEmailFromPathname(pathname)),
        [urls.audience(':tab' as AudienceTab)]: ({ tab }) =>
            actions.setCurrentTab(isAudienceTab(tab) ? tab : DEFAULT_AUDIENCE_TAB),
    })),
])
