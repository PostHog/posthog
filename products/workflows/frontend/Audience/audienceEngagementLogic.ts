import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import api from 'lib/api'
import { AppMetricsTotalsResponse, loadAppMetricsTotals } from 'lib/components/AppMetrics/appMetricsLogic'
import { dayjs } from 'lib/dayjs'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import type { DashboardApi } from 'products/dashboards/frontend/generated/api.schemas'

import { engagementEventsLogic } from '../engagementEventsLogic'
import { AudienceEngagementTileKey, audienceEngagementDashboardTemplate } from './audienceEngagementTiles'

export interface EmailMetricsTotals {
    sent: number
    delivered: number
    opened: number
    clicked: number
    bounced: number
    markedAsSpam: number
}

const METRIC_NAMES: Record<keyof EmailMetricsTotals, string> = {
    sent: 'email_sent',
    delivered: 'email_delivered',
    opened: 'email_opened',
    clicked: 'email_link_clicked',
    bounced: 'email_bounced',
    markedAsSpam: 'email_blocked',
}

export const METRICS_TOTALS_PERIOD_DAYS = 30

function toEmailMetricsTotals(response: AppMetricsTotalsResponse): EmailMetricsTotals {
    const totalFor = (metricName: string): number => response[metricName]?.total ?? 0
    return {
        sent: totalFor(METRIC_NAMES.sent),
        delivered: totalFor(METRIC_NAMES.delivered),
        opened: totalFor(METRIC_NAMES.opened),
        clicked: totalFor(METRIC_NAMES.clicked),
        bounced: totalFor(METRIC_NAMES.bounced),
        markedAsSpam: totalFor(METRIC_NAMES.markedAsSpam),
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceEngagementLogicValues {
    engagementEventsCaptured: boolean // engagementEventsLogic
    currentTeamId: number | null // teamLogic
    timezone: string // teamLogic
    createdDashboard: DashboardApi | null
    createdDashboardLoading: boolean
    metricsTotals: EmailMetricsTotals | null
    metricsTotalsFailed: boolean
    metricsTotalsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceEngagementLogicActions {
    createDashboard: () => any
    createDashboardFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    createDashboardSuccess: (
        createdDashboard: DashboardApi,
        payload?: any
    ) => {
        createdDashboard: DashboardApi
        payload?: any
    }
    insightOpened: (tile: AudienceEngagementTileKey) => {
        tile: AudienceEngagementTileKey
    }
    loadMetricsTotals: () => any
    loadMetricsTotalsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadMetricsTotalsSuccess: (
        metricsTotals: EmailMetricsTotals,
        payload?: any
    ) => {
        metricsTotals: EmailMetricsTotals
        payload?: any
    }
}

export type audienceEngagementLogicType = MakeLogicType<audienceEngagementLogicValues, audienceEngagementLogicActions>

export const audienceEngagementLogic = kea<audienceEngagementLogicType>([
    path(['products', 'workflows', 'frontend', 'Audience', 'audienceEngagementLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId', 'timezone'], engagementEventsLogic, ['engagementEventsCaptured']],
    })),
    actions({
        insightOpened: (tile: AudienceEngagementTileKey) => ({ tile }),
    }),
    loaders(({ values }) => ({
        createdDashboard: [
            null as DashboardApi | null,
            {
                createDashboard: async () => {
                    // nosemgrep: prefer-codegen-api -- dashboardsCreateFromTemplateJsonCreate() serves this route, but its generated types describe a dashboard body and a void response instead of the template body and the created dashboard.
                    return await api.create<DashboardApi>(
                        `api/projects/${values.currentTeamId}/dashboards/create_from_template_json`,
                        { template: audienceEngagementDashboardTemplate() }
                    )
                },
            },
        ],
        metricsTotals: [
            null as EmailMetricsTotals | null,
            {
                loadMetricsTotals: async () => {
                    const response = await loadAppMetricsTotals(
                        {
                            appSource: 'hog_flow',
                            metricName: Object.values(METRIC_NAMES),
                            breakdownBy: ['metric_name'],
                            dateFrom: dayjs().subtract(METRICS_TOTALS_PERIOD_DAYS, 'day').toISOString(),
                            dateTo: dayjs().toISOString(),
                        },
                        values.timezone
                    )
                    return toEmailMetricsTotals(response)
                },
            },
        ],
    })),
    reducers({
        metricsTotalsFailed: [
            false,
            {
                loadMetricsTotals: () => false,
                loadMetricsTotalsFailure: () => true,
            },
        ],
    }),
    listeners(() => ({
        createDashboardSuccess: ({ createdDashboard }) => {
            // pinned: event name is a wire string
            posthog.capture('audience dashboard created', { dashboard_id: createdDashboard.id })
            router.actions.push(urls.dashboard(createdDashboard.id))
        },
        insightOpened: ({ tile }) => {
            // pinned: event name is a wire string
            posthog.capture('audience insight opened', { tile })
        },
    })),
    afterMount(({ actions, values }) => {
        if (!values.engagementEventsCaptured) {
            actions.loadMetricsTotals()
        }
    }),
])
