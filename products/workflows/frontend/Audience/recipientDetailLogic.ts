import { LogicWrapper, MakeLogicType, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { ApiConfig, ApiError } from 'lib/api'

import { messagingRecipientsRetrieve } from 'products/messaging/frontend/generated/api'
import type { RecipientApi } from 'products/messaging/frontend/generated/api.schemas'

export interface RecipientDetailLogicProps {
    email: string
}

export type RecipientDetailView =
    | { state: 'loading' }
    | { state: 'error' }
    | { state: 'not-found' }
    | { state: 'found'; recipient: RecipientApi }

/** The lookup's answer: the recipient, or `null` when the team does not know the address. */
type RecipientLookup = RecipientApi | null

const NOT_LOOKED_UP = undefined

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface recipientDetailLogicValues {
    loadFailed: boolean
    recipient: RecipientLookup | undefined
    recipientLoading: boolean
    recipientView: RecipientDetailView
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface recipientDetailLogicActions {
    loadRecipient: () => {
        value: true
    }
    loadRecipientFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRecipientSuccess: (
        recipient: RecipientLookup | undefined,
        payload?: {
            value: true
        }
    ) => {
        recipient: RecipientLookup | undefined
        payload?: {
            value: true
        }
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface recipientDetailLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        recipientView: (
            recipient: RecipientLookup | undefined,
            recipientLoading: boolean,
            loadFailed: boolean
        ) => RecipientDetailView
    }
}

export type recipientDetailLogicType = MakeLogicType<
    recipientDetailLogicValues,
    recipientDetailLogicActions,
    RecipientDetailLogicProps,
    recipientDetailLogicMeta
>

function isNotFound(error: unknown): boolean {
    return error instanceof ApiError && error.status === 404
}

async function lookUpRecipient(email: string): Promise<RecipientLookup> {
    try {
        const page = await messagingRecipientsRetrieve(String(ApiConfig.getCurrentTeamId()), { email })
        return page.results[0] ?? null
    } catch (error) {
        if (isNotFound(error)) {
            return null
        }
        throw error
    }
}

export const recipientDetailLogic: LogicWrapper<recipientDetailLogicType> = kea<recipientDetailLogicType>([
    props({} as RecipientDetailLogicProps),
    key((props) => props.email),
    path((key) => ['products', 'workflows', 'frontend', 'Audience', 'recipientDetailLogic', key]),
    loaders(({ props }) => ({
        recipient: [
            NOT_LOOKED_UP as RecipientLookup | undefined,
            {
                loadRecipient: async () => await lookUpRecipient(props.email),
            },
        ],
    })),
    reducers({
        loadFailed: [
            false,
            { loadRecipient: () => false, loadRecipientSuccess: () => false, loadRecipientFailure: () => true },
        ],
    }),
    selectors({
        recipientView: [
            (s) => [s.recipient, s.recipientLoading, s.loadFailed],
            (
                recipient: RecipientLookup | undefined,
                recipientLoading: boolean,
                loadFailed: boolean
            ): RecipientDetailView => {
                if (loadFailed) {
                    return { state: 'error' }
                }
                if (recipientLoading || recipient === NOT_LOOKED_UP) {
                    return { state: 'loading' }
                }
                return recipient ? { state: 'found', recipient } : { state: 'not-found' }
            },
        ],
    }),
    listeners(() => ({
        loadRecipientSuccess: ({ recipient }) => {
            if (recipient) {
                // pinned: event name is a wire string; never send the address
                posthog.capture('audience recipient opened')
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRecipient()
    }),
])
