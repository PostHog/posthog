import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import { router, urlToAction } from 'kea-router'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { urls } from 'scenes/urls'

import type { MessagingNavTabKey } from '../messagingTabs'
import type { AudienceTab } from './audienceSceneLogic'

// pinned: the `from` values of the "messaging tab redirected to audience" event
type MessagingSurface = 'workflows' | 'broadcasts'

const AUDIENCE_TAB_FOR_MOVED_TAB = {
    'opt-outs': 'topics',
    suppression: 'suppression',
} as const satisfies Partial<Record<MessagingNavTabKey, AudienceTab>>

type MovedTab = keyof typeof AUDIENCE_TAB_FOR_MOVED_TAB

export function isMovedTab(tab: string): tab is MovedTab {
    return tab in AUDIENCE_TAB_FOR_MOVED_TAB
}

export interface MovedTabLocation {
    from: MessagingSurface
    tab: MovedTab
}

const MESSAGING_SURFACE_URLS: Record<MessagingSurface, (tab: MovedTab) => string> = {
    workflows: urls.workflows,
    broadcasts: urls.broadcasts,
}

const MOVED_TAB_LOCATIONS: MovedTabLocation[] = (Object.keys(MESSAGING_SURFACE_URLS) as MessagingSurface[]).flatMap(
    (from) => (Object.keys(AUDIENCE_TAB_FOR_MOVED_TAB) as MovedTab[]).map((tab) => ({ from, tab }))
)

function movedTabUrl({ from, tab }: MovedTabLocation): string {
    return MESSAGING_SURFACE_URLS[from](tab)
}

function movedTabAt(pathname: string): MovedTabLocation | undefined {
    const path = removeProjectIdIfPresent(pathname)
    return MOVED_TAB_LOCATIONS.find((location) => movedTabUrl(location) === path)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface movedMessagingTabsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    movesTabsToAudience: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface movedMessagingTabsLogicActions {
    openMovedTab: (location: MovedTabLocation) => {
        location: MovedTabLocation
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface movedMessagingTabsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        movesTabsToAudience: (featureFlags: FeatureFlagsSet) => boolean
    }
}

export type movedMessagingTabsLogicType = MakeLogicType<
    movedMessagingTabsLogicValues,
    movedMessagingTabsLogicActions,
    Record<string, any>,
    movedMessagingTabsLogicMeta
>

/** Sends the Opt-outs and Suppression list tabs of Workflows and Broadcasts to Audience while workflows-audience is on. */
export const movedMessagingTabsLogic = kea<movedMessagingTabsLogicType>([
    path(['products', 'workflows', 'frontend', 'Audience', 'movedMessagingTabsLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),
    actions({
        openMovedTab: (location: MovedTabLocation) => ({ location }),
    }),
    selectors({
        movesTabsToAudience: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.WORKFLOWS_AUDIENCE],
        ],
    }),
    listeners(({ actions, values }) => ({
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
            const location = movedTabAt(router.values.location.pathname)
            if (location) {
                actions.openMovedTab(location)
            }
        },
        openMovedTab: ({ location }) => {
            if (!values.movesTabsToAudience) {
                return
            }
            // pinned: analytics event name
            posthog.capture('messaging tab redirected to audience', { tab: location.tab, from: location.from })
            router.actions.replace(urls.audience(AUDIENCE_TAB_FOR_MOVED_TAB[location.tab]))
        },
    })),
    urlToAction(({ actions }) =>
        Object.fromEntries(
            MOVED_TAB_LOCATIONS.map((location) => [movedTabUrl(location), () => actions.openMovedTab(location)])
        )
    ),
])
