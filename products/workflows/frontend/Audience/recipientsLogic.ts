import * as api from 'products/messaging/frontend/generated/api'
import type { RecipientApi, RecipientPageApi } from 'products/messaging/frontend/generated/api.schemas'

import { MessageCategory, optOutCategoriesLogic } from '../OptOuts/optOutCategoriesLogic'

export const RECIPIENTS_PAGE_SIZE = 50
const SEARCH_DEBOUNCE_MS = 300

export type RecipientsView = 'loading' | 'error' | 'empty' | 'no-match' | 'results'

/** One page of one search: `pageCursors` holds the cursor of every page before it, the last one fetches it. */
export interface RecipientsRequest {
    search: string
    pageCursors: string[]
}

const FIRST_PAGE: RecipientsRequest = { search: '', pageCursors: [] }
const EMPTY_PAGE: RecipientPageApi = { results: [], next_cursor: null }

