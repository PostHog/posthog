function currentTeamId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

function firstPage(query: string): RecipientsRequest {
    return { query, pageCursors: [] }
}

/** The generated client joins a list into one `filter=a,b`; the API reads one `filter` per value. */
function recipientsPageUrl({ query, pageCursors }: RecipientsRequest): string {
    const searchValue = parseRecipientSearch(query)
    const url = api.getMessagingRecipientsRetrieveUrl(currentTeamId(), {
        search: searchValue.text || undefined,
        cursor: pageCursors.at(-1),
        limit: RECIPIENTS_PAGE_SIZE,
    })
    const filters = new URLSearchParams(recipientFilterParams(searchValue).map((filter) => ['filter', filter]))
    return filters.toString() ? `${url}&${filters}` : url
}

function searchQueryFromUrl(searchParams: Record<string, unknown>): string {
    const query = searchParams[SEARCH_URL_PARAM]
    if (query === undefined || query === null) {
        return ''
    }
    return typeof query === 'string' ? query : JSON.stringify(query)
}

/** The API names a filter it can't read, such as `person:non` typed and closed with a space. */
function rejectedFilterOf(error: unknown): string | null {
    if (error instanceof ApiError && error.status === 400 && error.attr === 'filter' && error.detail) {
        return error.detail.replaceAll('`', '"')
    }
    return null
}

function pillsOf(query: string): string {
    return recipientFilterParams(parseRecipientSearch(query)).join(' ')
}

export const recipientsLogic = kea<recipientsLogicType>([
    path(['products', 'workflows', 'frontend', 'Audience', 'recipientsLogic']),
    connect(() => ({ values: [optOutCategoriesLogic, ['categories']] })),
    actions({
        setSearchValue: (searchValue: FacetSearchValue) => ({ searchValue }),
        restoreSearchValue: (searchValue: FacetSearchValue) => ({ searchValue }),
        clearSearch: true,
        loadAudienceRecipients: (request: RecipientsRequest) => request,
        loadNextPage: true,
        loadPreviousPage: true,
        retryLoadRecipients: true,
        openUnreachablePersons: true,
    }),
    reducers({
        searchValue: [
            EMPTY_SEARCH,
            {
                setSearchValue: (_, { searchValue }) => withFixedValues(searchValue),
                restoreSearchValue: (_, { searchValue }) => searchValue,
                clearSearch: () => EMPTY_SEARCH,
            },
        ],
        lastRequest: [null as RecipientsRequest | null, { loadAudienceRecipients: (_, request) => request }],
        shownRequest: [firstPage(''), { loadAudienceRecipientsSuccess: (shown, { payload }) => payload ?? shown }],
        rejectedFilter: [
            null as string | null,
            {
                loadAudienceRecipients: () => null,
                loadAudienceRecipientsFailure: (_, { errorObject }) => rejectedFilterOf(errorObject),
            },
        ],
        loadFailed: [
            false,
            {
                loadAudienceRecipients: () => false,
                loadAudienceRecipientsSuccess: () => false,
                loadAudienceRecipientsFailure: () => true,
            },
        ],
    }),
    loaders(() => ({
        page: [
            EMPTY_PAGE,
            {
                loadAudienceRecipients: async (request, breakpoint): Promise<RecipientPageApi> => {
                    try {
                        const page = await apiMutator<RecipientPageApi>(recipientsPageUrl(request), { method: 'GET' })
                        breakpoint()
                        return page
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
        coverage: [
            null as number | null,
            {
                loadAudienceCoverage: async (): Promise<number | null> => {
                    const coverage = await api.messagingRecipientsCoverageRetrieve(currentTeamId())
                    return coverage.persons_without_email
                },
            },
        ],
    })),
    selectors({
        facets: [
            (s) => [s.categories],
            (categories: MessageCategoryApi[]): ServerFacet[] => recipientFacets(categories),
        ],
        searchQuery: [
            (s) => [s.searchValue],
            (searchValue: FacetSearchValue): string => serializeFacetSearch(searchValue),
        ],
        recipients: [(s) => [s.page], (page: RecipientPageApi): RecipientApi[] => page.results],
        searchPending: [
            (s) => [s.searchQuery, s.shownRequest],
            (searchQuery: string, shownRequest: RecipientsRequest): boolean => searchQuery !== shownRequest.query,
        ],
        canPage: [
            (s) => [s.pageLoading, s.searchPending],
            (pageLoading: boolean, searchPending: boolean): boolean => !pageLoading && !searchPending,
        ],
        hasNextPage: [
            (s) => [s.page, s.canPage],
            (page: RecipientPageApi, canPage: boolean): boolean => canPage && page.next_cursor !== null,
        ],
        hasPreviousPage: [
            (s) => [s.shownRequest, s.canPage],
            (shownRequest: RecipientsRequest, canPage: boolean): boolean =>
                canPage && shownRequest.pageCursors.length > 0,
        ],
        personsWithoutEmail: [(s) => [s.coverage], (coverage: number | null): number => coverage ?? 0],
        recipientsView: [
            (s) => [s.pageLoading, s.loadFailed, s.rejectedFilter, s.recipients, s.shownRequest, s.lastRequest],
            (
                pageLoading: boolean,
                loadFailed: boolean,
                rejectedFilter: string | null,
                recipients: RecipientApi[],
                shownRequest: RecipientsRequest,
                lastRequest: RecipientsRequest | null
            ): RecipientsView => {
                if (rejectedFilter) {
                    return 'rejected-filter'
                }
                const failedWhilePaging = recipients.length > 0 && lastRequest?.query === shownRequest.query
                if (loadFailed && !failedWhilePaging) {
                    return 'error'
                }
                if (recipients.length > 0) {
                    return 'results'
                }
                if (pageLoading) {
                    return 'loading'
                }
                return shownRequest.query ? 'no-match' : 'empty'
            },
        ],
    }),
    listeners(({ actions, values }) => {
        const loadFirstPage = (query: string): void => {
            const { lastRequest, loadFailed } = values
            const alreadyRequested = lastRequest?.query === query && lastRequest.pageCursors.length === 0 && !loadFailed
            if (!alreadyRequested) {
                actions.loadAudienceRecipients(firstPage(query))
            }
        }
        return {
            setSearchValue: async (_, breakpoint) => {
                await breakpoint(SEARCH_DEBOUNCE_MS)
                const pillsChanged = pillsOf(values.searchQuery) !== pillsOf(values.lastRequest?.query ?? '')
                if (pillsChanged && values.searchValue.filters.length > 0) {
                    // pinned: feature usage event name, renaming it breaks the Audience funnel. Facet keys only, values can hold an address.
                    posthog.capture('audience recipients filtered', { facets: facetKeysInUse(values.searchValue) })
                }
                loadFirstPage(values.searchQuery)
            },
            restoreSearchValue: () => loadFirstPage(values.searchQuery),
            clearSearch: () => loadFirstPage(''),
            loadNextPage: () => {
                const nextCursor = values.page.next_cursor
                if (values.hasNextPage && nextCursor) {
                    const { query, pageCursors } = values.shownRequest
                    actions.loadAudienceRecipients({ query, pageCursors: [...pageCursors, nextCursor] })
                }
            },
            loadPreviousPage: () => {
                if (values.hasPreviousPage) {
                    const { query, pageCursors } = values.shownRequest
                    actions.loadAudienceRecipients({ query, pageCursors: pageCursors.slice(0, -1) })
                }
            },
            retryLoadRecipients: () => {
                if (values.lastRequest) {
                    actions.loadAudienceRecipients(values.lastRequest)
                }
            },
            openUnreachablePersons: () => {
                // pinned: feature usage event name, renaming it breaks the Audience funnel
                posthog.capture('audience unreachable persons opened', { count: values.personsWithoutEmail })
            },
        }
    }),
    actionToUrl(({ values }) => {
        const searchToUrl = (): [string, Record<string, any>, Record<string, any>, { replace: true }] => {
            const { [SEARCH_URL_PARAM]: _, ...otherParams } = router.values.searchParams
            const searchParams = values.searchQuery
                ? { ...otherParams, [SEARCH_URL_PARAM]: values.searchQuery }
                : otherParams
            return [router.values.location.pathname, searchParams, router.values.hashParams, { replace: true }]
        }
        return { setSearchValue: searchToUrl, clearSearch: searchToUrl }
    }),
    urlToAction(({ actions, values }) => {
        const restoreSearchFromUrl = (
            _: Record<string, string | undefined>,
            searchParams: Record<string, unknown>
        ): void => {
            const query = searchQueryFromUrl(searchParams)
            if (query !== values.searchQuery) {
                actions.restoreSearchValue(parseRecipientSearch(query))
            }
        }
        return { [urls.audience()]: restoreSearchFromUrl, [urls.audience('recipients')]: restoreSearchFromUrl }
    }),
    afterMount(({ actions, values }) => {
        if (values.lastRequest === null) {
            actions.loadAudienceRecipients(firstPage(values.searchQuery))
        }
        actions.loadAudienceCoverage()
    }),
])
