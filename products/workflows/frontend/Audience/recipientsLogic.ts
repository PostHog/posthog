function currentTeamId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

export const recipientsLogic = kea<recipientsLogicType>([
    path(['products', 'workflows', 'frontend', 'Audience', 'recipientsLogic']),
    connect(() => ({ values: [optOutCategoriesLogic, ['categories']] })),
    actions({
        setSearch: (search: string) => ({ search }),
        loadAudienceRecipients: (request: RecipientsRequest) => request,
        loadNextPage: true,
        loadPreviousPage: true,
        retryLoadRecipients: true,
        openUnreachablePersons: true,
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        lastRequest: [FIRST_PAGE, { loadAudienceRecipients: (_, request) => request }],
        shownRequest: [FIRST_PAGE, { loadAudienceRecipientsSuccess: (shown, { payload }) => payload ?? shown }],
        loadFailed: [
            false,
            {
                loadAudienceRecipients: () => false,
                loadAudienceRecipientsSuccess: () => false,
                loadAudienceRecipientsFailure: () => true,
            },
        ],
        accessDenied: [
            false,
            {
                loadAudienceRecipients: () => false,
                loadAudienceRecipientsSuccess: () => false,
                loadAudienceRecipientsFailure: (_, { errorObject }) => errorObject?.status === 403,
            },
        ],
    }),
    loaders(() => ({
        page: [
            EMPTY_PAGE,
            {
                loadAudienceRecipients: async ({ search, pageCursors }, breakpoint): Promise<RecipientPageApi> => {
                    try {
                        const page = await api.messagingRecipientsRetrieve(currentTeamId(), {
                            search: search || undefined,
                            cursor: pageCursors.at(-1),
                            limit: RECIPIENTS_PAGE_SIZE,
                        })
                        breakpoint()
                        return page
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
        coverage: [
            null as number | null,
            {
                loadAudienceCoverage: async (): Promise<number | null> => {
                    const coverage = await api.messagingRecipientsCoverageRetrieve(currentTeamId())
                    return coverage.persons_without_email
                },
            },
        ],
    })),
    selectors({
        recipients: [(s) => [s.page], (page: RecipientPageApi): RecipientApi[] => page.results],
        searchPending: [
            (s) => [s.search, s.shownRequest],
            (search: string, shownRequest: RecipientsRequest): boolean => search.trim() !== shownRequest.search,
        ],
        canPage: [
            (s) => [s.pageLoading, s.searchPending],
            (pageLoading: boolean, searchPending: boolean): boolean => !pageLoading && !searchPending,
        ],
        hasNextPage: [(s) => [s.page], (page: RecipientPageApi): boolean => page.next_cursor !== null],
        hasPreviousPage: [
            (s) => [s.shownRequest],
            (shownRequest: RecipientsRequest): boolean => shownRequest.pageCursors.length > 0,
        ],
        topicNames: [
            (s) => [s.categories],
            (categories: MessageCategory[]): Record<string, string> =>
                Object.fromEntries(categories.map((category) => [category.key, category.name])),
        ],
        personsWithoutEmail: [(s) => [s.coverage], (coverage: number | null): number => coverage ?? 0],
        recipientsView: [
            (s) => [s.pageLoading, s.loadFailed, s.recipients, s.shownRequest, s.lastRequest],
            (
                pageLoading: boolean,
                loadFailed: boolean,
                recipients: RecipientApi[],
                shownRequest: RecipientsRequest,
                lastRequest: RecipientsRequest
            ): RecipientsView => {
                const showsTable = recipients.length > 0 || shownRequest.pageCursors.length > 0
                const failedWhilePaging = showsTable && lastRequest.search === shownRequest.search
                if (loadFailed && !failedWhilePaging) {
                    return 'error'
                }
                if (showsTable) {
                    return 'results'
                }
                if (pageLoading) {
                    return 'loading'
                }
                return shownRequest.search ? 'no-match' : 'empty'
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setSearch: async ({ search }, breakpoint) => {
            await breakpoint(SEARCH_DEBOUNCE_MS)
            if (search.trim() !== values.lastRequest.search) {
                actions.loadAudienceRecipients({ search: search.trim(), pageCursors: [] })
            }
        },
        loadNextPage: () => {
            const nextCursor = values.page.next_cursor
            if (values.canPage && nextCursor) {
                const { search, pageCursors } = values.shownRequest
                actions.loadAudienceRecipients({ search, pageCursors: [...pageCursors, nextCursor] })
            }
        },
        loadPreviousPage: () => {
            if (values.canPage && values.hasPreviousPage) {
                const { search, pageCursors } = values.shownRequest
                actions.loadAudienceRecipients({ search, pageCursors: pageCursors.slice(0, -1) })
            }
        },
        retryLoadRecipients: () => actions.loadAudienceRecipients(values.lastRequest),
        openUnreachablePersons: () => {
            // pinned: feature usage event name, renaming it breaks the Audience funnel
            posthog.capture('audience unreachable persons opened', { count: values.personsWithoutEmail })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadAudienceRecipients(FIRST_PAGE)
        actions.loadAudienceCoverage()
    }),
])
