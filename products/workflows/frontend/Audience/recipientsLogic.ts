function currentTeamId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

export const recipientsLogic = kea<recipientsLogicType>([
    path(['products', 'workflows', 'frontend', 'Audience', 'recipientsLogic']),
    connect(() => ({ values: [optOutCategoriesLogic, ['categories']] })),
    actions({
        setSearch: (search: string) => ({ search }),
        clearSearch: true,
        loadAudienceRecipients: (request: RecipientsRequest) => request,
        loadNextPage: true,
        loadPreviousPage: true,
        retryLoadRecipients: true,
        openUnreachablePersons: true,
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search, clearSearch: () => '' }],
        lastRequest: [FIRST_PAGE, { loadAudienceRecipients: (_, request) => request }],
        shownRequest: [FIRST_PAGE, { loadAudienceRecipientsSuccess: (shown, { payload }) => payload ?? shown }],
        loadFailed: [
            false,
            {
                loadAudienceRecipients: () => false,
                loadAudienceRecipientsSuccess: () => false,
                loadAudienceRecipientsFailure: () => true,
            },
        ],
        accessDenied: [
            false,
            {
                loadAudienceRecipients: () => false,
                loadAudienceRecipientsSuccess: () => false,
                loadAudienceRecipientsFailure: (_, { errorObject }) => isAccessDeniedError(errorObject ?? {}),
            },
        ],
    }),
    loaders(() => ({
        page: [
            EMPTY_PAGE,
            {
                loadAudienceRecipients: async ({ search, pageCursors }, breakpoint): Promise<RecipientPageApi> => {
                    try {
                        const page = await api.messagingRecipientsRetrieve(currentTeamId(), {
                            search: search || undefined,
                            cursor: pageCursors.at(-1),
                            limit: RECIPIENTS_PAGE_SIZE,
                        })
                        breakpoint()
                        return page
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                },
            },
        ],
        personsWithoutEmail: [
            0,
            {
                loadAudienceCoverage: async (): Promise<number> => {
                    const coverage = await api.messagingRecipientsCoverageRetrieve(currentTeamId())
                    return coverage.persons_without_email
                },
            },
        ],
    })),
    selectors({
        recipients: [
            (s) => [s.page, s.recipientsView],
            (page: RecipientPageApi, recipientsView: RecipientsView): RecipientApi[] =>
                recipientsView === 'results' ? page.results : [],
        ],
        searchPending: [
            (s) => [s.search, s.shownRequest],
            (search: string, shownRequest: RecipientsRequest): boolean => search.trim() !== shownRequest.search,
        ],
        canPage: [
            (s) => [s.pageLoading, s.searchPending],
            (pageLoading: boolean, searchPending: boolean): boolean => !pageLoading && !searchPending,
        ],
        currentPage: [
            (s) => [s.recipientsView, s.shownRequest],
            (recipientsView: RecipientsView, shownRequest: RecipientsRequest): number | null =>
                recipientsView === 'results' ? shownRequest.pageCursors.length + 1 : null,
        ],
        hasNextPage: [
            (s) => [s.recipientsView, s.page],
            (recipientsView: RecipientsView, page: RecipientPageApi): boolean =>
                recipientsView === 'results' && page.next_cursor !== null,
        ],
        hasPreviousPage: [
            (s) => [s.currentPage],
            (currentPage: number | null): boolean => currentPage !== null && currentPage > 1,
        ],
        topicNames: [
            (s) => [s.categories],
            (categories: MessageCategory[]): Record<string, string> =>
                Object.fromEntries(categories.map((category) => [category.key, category.name])),
        ],
        recipientsView: [
            (s) => [s.pageLoading, s.loadFailed, s.page, s.shownRequest, s.lastRequest],
            (
                pageLoading: boolean,
                loadFailed: boolean,
                page: RecipientPageApi,
                shownRequest: RecipientsRequest,
                lastRequest: RecipientsRequest
            ): RecipientsView => {
                if (pageLoading && lastRequest.search !== shownRequest.search) {
                    return 'loading'
                }
                const showsTable = page.results.length > 0 || shownRequest.pageCursors.length > 0
                const failedWhilePaging = showsTable && lastRequest.search === shownRequest.search
                if (loadFailed && !failedWhilePaging) {
                    return 'error'
                }
                if (showsTable) {
                    return 'results'
                }
                if (pageLoading) {
                    return 'loading'
                }
                return shownRequest.search ? 'no-match' : 'empty'
            },
        ],
    }),
    listeners(({ actions, values, selectors }) => ({
        setSearch: async (_, breakpoint) => {
            await breakpoint(SEARCH_DEBOUNCE_MS)
            const search = values.search.trim()
            if (search === values.lastRequest.search) {
                return
            }
            actions.loadAudienceRecipients({ search, pageCursors: [] })
            if (!search) {
                captureRecipientsUsage('audience recipients search cleared', {})
            }
        },
        clearSearch: () => {
            actions.loadAudienceRecipients(FIRST_PAGE)
            captureRecipientsUsage('audience recipients search cleared', {})
        },
        loadAudienceRecipientsSuccess: ({ page, payload }, _, __, previousState) => {
            const landedNewSearch = !!payload?.search && payload.search !== selectors.shownRequest(previousState).search
            if (landedNewSearch) {
                captureRecipientsUsage('audience recipients filtered', { has_results: page.results.length > 0 })
            }
        },
        loadNextPage: () => {
            const nextCursor = values.page.next_cursor
            if (values.canPage && nextCursor) {
                const { search, pageCursors } = values.shownRequest
                actions.loadAudienceRecipients({ search, pageCursors: [...pageCursors, nextCursor] })
                captureRecipientsUsage('audience recipients paged', { direction: 'next' })
            }
        },
        loadPreviousPage: () => {
            if (values.canPage && values.hasPreviousPage) {
                const { search, pageCursors } = values.shownRequest
                actions.loadAudienceRecipients({ search, pageCursors: pageCursors.slice(0, -1) })
                captureRecipientsUsage('audience recipients paged', { direction: 'previous' })
            }
        },
        retryLoadRecipients: () => {
            actions.loadAudienceRecipients(values.lastRequest)
            captureRecipientsUsage('audience recipients retried', {})
        },
        openUnreachablePersons: () => {
            captureRecipientsUsage('audience unreachable persons opened', { count: values.personsWithoutEmail })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadAudienceRecipients(FIRST_PAGE)
        actions.loadAudienceCoverage()
    }),
])
