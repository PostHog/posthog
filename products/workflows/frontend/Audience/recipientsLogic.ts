function currentTeamId(): string {
    return String(ApiConfig.getCurrentTeamId())
}

export const recipientsLogic = kea<recipientsLogicType>([
    path(['products', 'workflows', 'frontend', 'Audience', 'recipientsLogic']),
    actions({
        setSearch: (search: string) => ({ search }),
        loadNextPage: true,
        loadPreviousPage: true,
        setPageCursors: (pageCursors: string[]) => ({ pageCursors }),
        loadAudienceRecipients: (request: RecipientsRequest) => request,
        retryLoadRecipients: true,
        openUnreachablePersons: true,
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        pageCursors: [
            [] as string[],
            {
                setSearch: () => [],
                setPageCursors: (_, { pageCursors }) => pageCursors,
            },
        ],
        loadedSearch: ['', { loadAudienceRecipients: (_, { search }) => search }],
        loadFailed: [
            false,
            {
                loadAudienceRecipients: () => false,
                loadAudienceRecipientsFailure: () => true,
            },
        ],
    }),
    loaders(() => ({
        page: [
            EMPTY_PAGE,
            {
                loadAudienceRecipients: async ({ search, cursor }, breakpoint): Promise<RecipientPageApi> => {
                    const page = await api.messagingRecipientsRetrieve(currentTeamId(), {
                        search: search || undefined,
                        cursor,
                        limit: RECIPIENTS_PAGE_SIZE,
                    })
                    breakpoint()
                    return page
                },
            },
        ],
        coverage: [
            null as number | null,
            {
                loadCoverage: async (): Promise<number | null> => {
                    const coverage = await api.messagingRecipientsCoverageRetrieve(currentTeamId())
                    return coverage.persons_without_email
                },
            },
        ],
    })),
    selectors({
        recipients: [(s) => [s.page], (page: RecipientPageApi): RecipientApi[] => page.results],
        hasNextPage: [(s) => [s.page], (page: RecipientPageApi): boolean => page.next_cursor !== null],
        hasPreviousPage: [(s) => [s.pageCursors], (pageCursors: string[]): boolean => pageCursors.length > 0],
        personsWithoutEmail: [(s) => [s.coverage], (coverage: number | null): number => coverage ?? 0],
        recipientsView: [
            (s) => [s.pageLoading, s.loadFailed, s.recipients, s.loadedSearch],
            (
                pageLoading: boolean,
                loadFailed: boolean,
                recipients: RecipientApi[],
                loadedSearch: string
            ): RecipientsView => {
                if (loadFailed) {
                    return 'error'
                }
                if (recipients.length > 0) {
                    return 'results'
                }
                if (pageLoading) {
                    return 'loading'
                }
                return loadedSearch ? 'no-match' : 'empty'
            },
        ],
    }),
    listeners(({ actions, values }) => {
        const loadPageAt = (cursor: string | undefined): void => {
            actions.loadAudienceRecipients({ search: values.search, cursor })
        }
        return {
            setSearch: async (_, breakpoint) => {
                await breakpoint(SEARCH_DEBOUNCE_MS)
                loadPageAt(undefined)
            },
            loadNextPage: () => {
                const nextCursor = values.page.next_cursor
                if (nextCursor) {
                    actions.setPageCursors([...values.pageCursors, nextCursor])
                    loadPageAt(nextCursor)
                }
            },
            loadPreviousPage: () => {
                const pageCursors = values.pageCursors.slice(0, -1)
                actions.setPageCursors(pageCursors)
                loadPageAt(pageCursors.at(-1))
            },
            retryLoadRecipients: () => loadPageAt(values.pageCursors.at(-1)),
            openUnreachablePersons: () => {
                // pinned: feature usage event name, renaming it breaks the Audience funnel
                posthog.capture('audience unreachable persons opened', { count: values.personsWithoutEmail })
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadAudienceRecipients({ search: '' })
        actions.loadCoverage()
    }),
])
