import { MakeLogicType, afterMount, connect, kea, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { AppMetricsTotalsResponse, loadAppMetricsTotals } from 'lib/components/AppMetrics/appMetricsLogic'
import { dayjs } from 'lib/dayjs'
import { dateStringToDayJs } from 'lib/utils/dateFilters'
import { teamLogic } from 'scenes/teamLogic'

export interface EmailMetricsTotals {
    sent: number
    delivered: number
    opened: number
    clicked: number
    bounced: number
    markedAsSpam: number
}

const METRIC_NAMES: Record<keyof EmailMetricsTotals, string> = {
    sent: 'email_sent',
    delivered: 'email_delivered',
    opened: 'email_opened',
    clicked: 'email_link_clicked',
    bounced: 'email_bounced',
    markedAsSpam: 'email_blocked',
}

export const METRICS_TOTALS_PERIOD_DAYS = 30

function toEmailMetricsTotals(response: AppMetricsTotalsResponse): EmailMetricsTotals {
    const totals = Object.entries(METRIC_NAMES).map(([key, metricName]) => [key, response[metricName]?.total ?? 0])
    return Object.fromEntries(totals) as EmailMetricsTotals
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface emailMetricsTotalsLogicValues {
    timezone: string // teamLogic
    metricsTotals: EmailMetricsTotals | null
    metricsTotalsError: string | null
    metricsTotalsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface emailMetricsTotalsLogicActions {
    loadMetricsTotals: () => any
    loadMetricsTotalsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadMetricsTotalsSuccess: (
        metricsTotals: EmailMetricsTotals,
        payload?: any
    ) => {
        metricsTotals: EmailMetricsTotals
        payload?: any
    }
}

export type emailMetricsTotalsLogicType = MakeLogicType<emailMetricsTotalsLogicValues, emailMetricsTotalsLogicActions>

export const emailMetricsTotalsLogic = kea<emailMetricsTotalsLogicType>([
    path(['products', 'workflows', 'frontend', 'Audience', 'emailMetricsTotalsLogic']),
    connect(() => ({
        values: [teamLogic, ['timezone']],
    })),
    loaders(({ values }) => ({
        metricsTotals: [
            null as EmailMetricsTotals | null,
            {
                loadMetricsTotals: async () => {
                    const response = await loadAppMetricsTotals(
                        {
                            appSource: 'hog_flow',
                            metricName: Object.values(METRIC_NAMES),
                            breakdownBy: ['metric_name'],
                            dateFrom: dateStringToDayJs(
                                `-${METRICS_TOTALS_PERIOD_DAYS}d`,
                                values.timezone
                            )?.toISOString(),
                            dateTo: dayjs().toISOString(),
                        },
                        values.timezone
                    )
                    return toEmailMetricsTotals(response)
                },
            },
        ],
    })),
    reducers({
        metricsTotalsError: [
            null as string | null,
            {
                loadMetricsTotals: () => null,
                loadMetricsTotalsFailure: (_, { error }) => error,
            },
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadMetricsTotals()
    }),
])
