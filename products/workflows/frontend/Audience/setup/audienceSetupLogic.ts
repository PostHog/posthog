import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { apiHostOrigin } from 'lib/utils/apiHost'
import { teamLogic } from 'scenes/teamLogic'

import { TeamPublicType, TeamType } from '~/types'

import { MessageCategory, optOutCategoriesLogic } from '../../OptOuts/optOutCategoriesLogic'
import { audienceSceneLogic } from '../audienceSceneLogic'
import { AudienceSetupSnippetContext, codingAgentPrompt, posthogNodeSnippet } from './audienceSetupSnippets'

// pinned: sent as the `variant` property of `audience snippet copied`
export type AudienceSnippetVariant = 'snippet' | 'agent_prompt'

const PROJECT_TOKEN_PLACEHOLDER = '<your project API key>'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceSetupLogicValues {
    setupPageOpen: boolean // audienceSceneLogic
    categories: MessageCategory[] // optOutCategoriesLogic
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    agentPrompt: string
    nodeSnippet: string
    snippetContext: AudienceSetupSnippetContext
    snippetVariant: AudienceSnippetVariant
    topicKeys: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceSetupLogicActions {
    setSnippetVariant: (variant: AudienceSnippetVariant) => {
        variant: AudienceSnippetVariant
    }
    trackSnippetCopied: (variant: AudienceSnippetVariant) => {
        variant: AudienceSnippetVariant
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface audienceSetupLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        topicKeys: (categories: MessageCategory[]) => string[]
        snippetContext: (
            currentTeam: TeamPublicType | TeamType | null,
            topicKeys: string[]
        ) => AudienceSetupSnippetContext
        nodeSnippet: (snippetContext: AudienceSetupSnippetContext) => string
        agentPrompt: (snippetContext: AudienceSetupSnippetContext) => string
    }
}

export type audienceSetupLogicType = MakeLogicType<
    audienceSetupLogicValues,
    audienceSetupLogicActions,
    Record<string, any>,
    audienceSetupLogicMeta
>

export const audienceSetupLogic = kea<audienceSetupLogicType>([
    path(['products', 'workflows', 'frontend', 'Audience', 'setup', 'audienceSetupLogic']),
    connect(() => ({
        values: [
            optOutCategoriesLogic,
            ['categories'],
            teamLogic,
            ['currentTeam'],
            audienceSceneLogic,
            ['setupPageOpen'],
        ],
    })),
    actions({
        setSnippetVariant: (variant: AudienceSnippetVariant) => ({ variant }),
        trackSnippetCopied: (variant: AudienceSnippetVariant) => ({ variant }),
    }),
    reducers({
        snippetVariant: ['snippet' as AudienceSnippetVariant, { setSnippetVariant: (_, { variant }) => variant }],
    }),
    selectors({
        topicKeys: [
            (s) => [s.categories],
            (categories: MessageCategory[]): string[] =>
                categories.filter((topic) => topic.category_type !== 'transactional').map((topic) => topic.key),
        ],
        snippetContext: [
            (s) => [s.currentTeam, s.topicKeys],
            (currentTeam: TeamPublicType | TeamType | null, topicKeys: string[]): AudienceSetupSnippetContext => ({
                projectToken: currentTeam?.api_token ?? PROJECT_TOKEN_PLACEHOLDER,
                host: apiHostOrigin(),
                topicKeys,
            }),
        ],
        nodeSnippet: [
            (s) => [s.snippetContext],
            (snippetContext: AudienceSetupSnippetContext): string => posthogNodeSnippet(snippetContext),
        ],
        agentPrompt: [
            (s) => [s.snippetContext],
            (snippetContext: AudienceSetupSnippetContext): string => codingAgentPrompt(snippetContext),
        ],
    }),
    listeners(() => ({
        trackSnippetCopied: ({ variant }) => {
            // pinned: feature usage event name, renaming it breaks the Audience setup funnel
            posthog.capture('audience snippet copied', { variant })
        },
    })),
    afterMount(({ values }) => {
        // pinned: feature usage event name and `source` values, renaming them breaks the Audience setup funnel
        posthog.capture('audience setup viewed', { source: values.setupPageOpen ? 'setup_page' : 'empty_state' })
    }),
])
