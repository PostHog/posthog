import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import api from 'lib/api'
import { projectLogic } from 'scenes/projectLogic'
import { urls } from 'scenes/urls'

import { hogql } from '~/queries/utils'

import {
    hogFlowTemplatesList,
    hogFlowsCreate,
    hogFlowsList,
    workflowDataSuggestionsBuild,
    workflowDataSuggestionsCurrent,
} from '../../generated/api'
import type { DataSuggestionsResponseApi } from '../../generated/api.schemas'
import type { HogFlowTemplate } from '../../Workflows/hogflows/types'
import { urlForNewWorkflowFromTemplate } from '../../Workflows/workflowTriggerPrefill'
import { SuggestionCard, cardFromAi, cardFromRules } from './suggestionCards'
import {
    WorkflowSuggestion,
    findSuggestionCandidates,
    suggestionTriggerConfig,
    rankSuggestions,
    withoutUsedEvents,
} from './workflowSuggestionRules'

// The definitions list is newest first, so this keeps the events a project still sends.
const EVENT_DEFINITIONS_LIMIT = 500

// pinned: analytics property values for the `workflows data suggestion*` events - renaming breaks dashboards
export type WorkflowDataSuggestionsSurface = 'empty_state'

export interface WorkflowDataSuggestionsLogicProps {
    surface: WorkflowDataSuggestionsSurface
}

