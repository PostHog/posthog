export const workflowDataSuggestionsLogic = kea<workflowDataSuggestionsLogicType>([
    path((surface) => [
        'products',
        'workflows',
        'frontend',
        'setupGuide',
        'suggestions',
        'workflowDataSuggestionsLogic',
        surface,
    ]),
    props({} as WorkflowDataSuggestionsLogicProps),
    key((props) => props.surface),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], projectLogic, ['currentProjectId']],
    })),
    actions({
        giveUpPolling: true,
        hideSuggestions: true,
        showSuggestions: true,
        setHidden: (teamId: string, hidden: boolean) => ({ teamId, hidden }),
        startSuggestion: (card: SuggestionCard) => ({ card }),
        setBuildingKey: (key: string | null) => ({ key }),
    }),
    reducers({
        buildingKey: [
            null as string | null,
            {
                setBuildingKey: (_, { key }) => key,
            },
        ],
        pollingTimedOut: [
            false,
            {
                giveUpPolling: () => true,
            },
        ],
        // Keyed by team ID, so hiding the suggestions in one project does not hide them in another.
        hiddenByTeam: [
            {} as Record<string, boolean>,
            { persist: true },
            {
                setHidden: (state, { teamId, hidden }) => ({ ...state, [teamId]: hidden }),
            },
        ],
    }),
    selectors({
        hidden: [
            (s) => [s.hiddenByTeam, s.currentTeamId],
            (hiddenByTeam: Record<string, boolean>, currentTeamId: number | null): boolean =>
                currentTeamId !== null && !!hiddenByTeam[String(currentTeamId)],
        ],
    }),
    loaders(({ values }) => ({
        aiResult: [
            null as DataSuggestionsResponseApi | null,
            {
                // Returns the cached cards, or starts a background run and answers with status generating.
                loadAiResult: async (): Promise<DataSuggestionsResponseApi | null> => {
                    try {
                        return await workflowDataSuggestionsGenerate(
                            String(values.currentProjectId),
                            {},
                            { signal: AbortSignal.timeout(POLL_REQUEST_TIMEOUT_MS) }
                        )
                    } catch {
                        // Suggestions are optional, so a failed call shows nothing rather than an error.
                        return null
                    }
                },
                pollAiResult: async (): Promise<DataSuggestionsResponseApi | null> => {
                    try {
                        return await workflowDataSuggestionsCurrent(String(values.currentProjectId), {
                            signal: AbortSignal.timeout(POLL_REQUEST_TIMEOUT_MS),
                        })
                    } catch {
                        return null
                    }
                },
            },
        ],
    })),
    selectors({
        cards: [
            (s) => [s.aiResult],
            (aiResult: DataSuggestionsResponseApi | null): SuggestionCard[] =>
                aiResult?.status === 'ready' ? aiResult.suggestions.map(cardFromSuggestion) : [],
        ],
        generating: [
            (s) => [s.aiResult, s.aiResultLoading, s.pollingTimedOut],
            (
                aiResult: DataSuggestionsResponseApi | null,
                aiResultLoading: boolean,
                pollingTimedOut: boolean
            ): boolean => !pollingTimedOut && (aiResultLoading || aiResult?.status === 'generating'),
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        // Both the first call and every poll land here: keep polling while the background run goes on.
        const handleResult = (aiResult: DataSuggestionsResponseApi | null): void => {
            // A response that lands after the lane was hidden neither polls nor counts as shown.
            if (values.hidden) {
                return
            }
            if (aiResult?.status === 'generating') {
                if (Date.now() > cache.pollDeadline) {
                    actions.giveUpPolling()
                    return
                }
                cache.disposables.add(() => {
                    const timer = window.setTimeout(() => actions.pollAiResult(), POLL_INTERVAL_MS)
                    return () => window.clearTimeout(timer)
                }, 'poll')
                return
            }
            if (aiResult?.status === 'ready' && aiResult.suggestions.length > 0) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows data suggestions shown', {
                    surface: props.surface,
                    source: 'ai',
                    trigger_events: aiResult.suggestions.map((suggestion) => suggestion.trigger_event),
                    stages: aiResult.suggestions.map((suggestion) => suggestion.stage),
                })
            }
        }
        return {
            loadAiResultSuccess: ({ aiResult }) => {
                cache.pollDeadline = Date.now() + POLL_DEADLINE_MS
                handleResult(aiResult)
            },
            pollAiResultSuccess: ({ aiResult }) => handleResult(aiResult),
            startSuggestion: async ({ card }, breakpoint) => {
                if (values.buildingKey) {
                    return
                }
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows data suggestion clicked', {
                    surface: props.surface,
                    source: 'ai',
                    trigger_event: card.triggerEvent,
                    weekly_count: card.weeklyCount,
                    stage: card.stage,
                })
                actions.setBuildingKey(card.key)
                const projectId = String(values.currentProjectId)
                const deadline = Date.now() + POLL_DEADLINE_MS
                // The timeout ends a stalled request at the deadline, so the buttons do not stay disabled.
                // Only the click retries a failed build. Polls read the failure, like every other tab does.
                const requestBuild = (retry: boolean): ReturnType<typeof workflowDataSuggestionsBuild> =>
                    workflowDataSuggestionsBuild(
                        projectId,
                        { suggestion_id: card.suggestionId, retry },
                        { signal: AbortSignal.timeout(Math.max(deadline - Date.now(), 0)) }
                    )
                try {
                    // The build runs in the background. Asking again is free while it runs, and breakpoint stops
                    // the loop, the save and the redirect once the person leaves the page.
                    let built = await requestBuild(true)
                    breakpoint()
                    while (built.status === 'building') {
                        if (Date.now() > deadline) {
                            throw new Error(BUILD_FAILED_MESSAGE)
                        }
                        await breakpoint(POLL_INTERVAL_MS)
                        built = await requestBuild(false)
                        breakpoint()
                    }
                    if (built.status !== 'ready') {
                        throw new Error(BUILD_FAILED_MESSAGE)
                    }
                    const workflow = await hogFlowsCreate(projectId, {
                        ...(built.workflow as Record<string, unknown>),
                        status: 'draft',
                    } as Parameters<typeof hogFlowsCreate>[1])
                    breakpoint()
                    // pinned: analytics event name - renaming breaks dashboards
                    posthog.capture('workflows data suggestion built', {
                        surface: props.surface,
                        trigger_event: card.triggerEvent,
                        stage: card.stage,
                        uses_saved_template: built.uses_saved_template,
                    })
                    router.actions.push(urls.workflow(workflow.id, 'workflow'))
                } catch (error: any) {
                    if (isBreakpoint(error)) {
                        throw error
                    }
                    lemonToast.error(
                        error?.name === 'TimeoutError'
                            ? BUILD_FAILED_MESSAGE
                            : error?.detail || error?.message || BUILD_FAILED_MESSAGE
                    )
                } finally {
                    if (!cache.disposables.isDisposed) {
                        actions.setBuildingKey(null)
                    }
                }
            },
            hideSuggestions: () => {
                if (values.currentTeamId === null) {
                    return
                }
                actions.setHidden(String(values.currentTeamId), true)
                cache.disposables.dispose('poll')
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows data suggestions hidden', { surface: props.surface })
            },
            showSuggestions: () => {
                if (values.currentTeamId === null) {
                    return
                }
                actions.setHidden(String(values.currentTeamId), false)
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows data suggestions unhidden', { surface: props.surface })
                if (values.aiResult === null || values.aiResult.status === 'generating') {
                    actions.loadAiResult()
                }
            },
        }
    }),
    afterMount(({ actions, values }) => {
        // A hidden lane shows no suggestions, so it skips the request until someone shows it again.
        if (!values.hidden) {
            actions.loadAiResult()
        }
    }),
])
