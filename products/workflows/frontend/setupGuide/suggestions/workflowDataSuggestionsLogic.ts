import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { projectLogic } from 'scenes/projectLogic'
import { urls } from 'scenes/urls'

import { hogFlowsCreate, workflowDataSuggestionsBuild, workflowDataSuggestionsCurrent } from '../../generated/api'
import type { DataSuggestionsResponseApi } from '../../generated/api.schemas'
import { SuggestionCard, cardFromSuggestion } from './suggestionCards'

// pinned: analytics property values for the `workflows data suggestion*` events - renaming breaks dashboards
export type WorkflowDataSuggestionsSurface = 'empty_state'

export interface WorkflowDataSuggestionsLogicProps {
    surface: WorkflowDataSuggestionsSurface
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowDataSuggestionsLogicValues {
    currentProjectId: number | null // projectLogic
    aiResult: DataSuggestionsResponseApi | null
    aiResultLoading: boolean
    buildingKey: string | null
    cards: SuggestionCard[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowDataSuggestionsLogicActions {
    loadAiResult: () => any
    loadAiResultFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAiResultSuccess: (
        aiResult: DataSuggestionsResponseApi | null,
        payload?: any
    ) => {
        aiResult: DataSuggestionsResponseApi | null
        payload?: any
    }
    setBuildingKey: (key: string | null) => {
        key: string | null
    }
    startSuggestion: (card: SuggestionCard) => {
        card: SuggestionCard
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface workflowDataSuggestionsLogicMeta {
    key: 'empty_state'
    __keaTypeGenInternalSelectorTypes: {
        cards: (aiResult: DataSuggestionsResponseApi | null) => SuggestionCard[]
    }
}

export type workflowDataSuggestionsLogicType = MakeLogicType<
    workflowDataSuggestionsLogicValues,
    workflowDataSuggestionsLogicActions,
    WorkflowDataSuggestionsLogicProps,
    workflowDataSuggestionsLogicMeta
>

export const workflowDataSuggestionsLogic = kea<workflowDataSuggestionsLogicType>([
    path((surface) => [
        'products',
        'workflows',
        'frontend',
        'setupGuide',
        'suggestions',
        'workflowDataSuggestionsLogic',
        surface,
    ]),
    props({} as WorkflowDataSuggestionsLogicProps),
    key((props) => props.surface),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        startSuggestion: (card: SuggestionCard) => ({ card }),
        setBuildingKey: (key: string | null) => ({ key }),
    }),
    reducers({
        buildingKey: [
            null as string | null,
            {
                setBuildingKey: (_, { key }) => key,
            },
        ],
    }),
    loaders(({ values }) => ({
        aiResult: [
            null as DataSuggestionsResponseApi | null,
            {
                loadAiResult: async (): Promise<DataSuggestionsResponseApi | null> => {
                    try {
                        return await workflowDataSuggestionsCurrent(String(values.currentProjectId))
                    } catch {
                        // Suggestions are optional, so a failed call shows nothing rather than an error.
                        return null
                    }
                },
            },
        ],
    })),
    selectors({
        cards: [
            (s) => [s.aiResult],
            (aiResult: DataSuggestionsResponseApi | null): SuggestionCard[] =>
                aiResult?.status === 'ready' ? aiResult.suggestions.map(cardFromSuggestion) : [],
        ],
    }),
    listeners(({ actions, values, props }) => ({
        loadAiResultSuccess: ({ aiResult }) => {
            if (aiResult?.status === 'ready' && aiResult.suggestions.length > 0) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows data suggestions shown', {
                    surface: props.surface,
                    source: 'ai',
                    trigger_events: aiResult.suggestions.map((suggestion) => suggestion.trigger_event),
                    stages: aiResult.suggestions.map((suggestion) => suggestion.stage),
                })
            }
        },
        startSuggestion: async ({ card }) => {
            if (values.buildingKey) {
                return
            }
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows data suggestion clicked', {
                surface: props.surface,
                source: 'ai',
                trigger_event: card.triggerEvent,
                weekly_count: card.weeklyCount,
                stage: card.stage,
            })
            actions.setBuildingKey(card.key)
            try {
                const projectId = String(values.currentProjectId)
                const built = await workflowDataSuggestionsBuild(projectId, { suggestion_id: card.suggestionId })
                const workflow = await hogFlowsCreate(projectId, {
                    ...(built.workflow as Record<string, unknown>),
                    status: 'draft',
                } as Parameters<typeof hogFlowsCreate>[1])
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows data suggestion built', {
                    surface: props.surface,
                    trigger_event: card.triggerEvent,
                    stage: card.stage,
                    uses_saved_template: built.uses_saved_template,
                    branded: !!built.brand_site_name,
                })
                router.actions.push(urls.workflow(workflow.id, 'workflow'))
            } catch (error: any) {
                lemonToast.error(
                    error?.detail || "We couldn't build this workflow. Try again, or start from a template."
                )
            } finally {
                actions.setBuildingKey(null)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadAiResult()
    }),
])
