export type workflowDataSuggestionsLogicType = MakeLogicType<
    workflowDataSuggestionsLogicValues,
    workflowDataSuggestionsLogicActions,
    WorkflowDataSuggestionsLogicProps,
    workflowDataSuggestionsLogicMeta
>

export const workflowDataSuggestionsLogic = kea<workflowDataSuggestionsLogicType>([
    path((surface) => [
        'products',
        'workflows',
        'frontend',
        'setupGuide',
        'suggestions',
        'workflowDataSuggestionsLogic',
        surface,
    ]),
    props({} as WorkflowDataSuggestionsLogicProps),
    key((props) => props.surface),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        startSuggestion: (card: SuggestionCard) => ({ card }),
        setBuildingKey: (key: string | null) => ({ key }),
    }),
    reducers({
        buildingKey: [
            null as string | null,
            {
                setBuildingKey: (_, { key }) => key,
            },
        ],
    }),
    loaders(({ values }) => ({
        aiResult: [
            null as DataSuggestionsResponseApi | null,
            {
                loadAiResult: async (): Promise<DataSuggestionsResponseApi | null> => {
                    try {
                        return await workflowDataSuggestionsCurrent(String(values.currentProjectId))
                    } catch {
                        // The rules-based cards stay on screen, so a failed AI call needs no error state.
                        return null
                    }
                },
            },
        ],
        suggestions: [
            [] as WorkflowSuggestion[],
            {
                loadSuggestions: async (): Promise<WorkflowSuggestion[]> => {
                    const [templates, definitions] = await Promise.all([
                        hogFlowTemplatesList(String(values.currentProjectId)),
                        api.eventDefinitions.list({ limit: EVENT_DEFINITIONS_LIMIT }),
                    ])
                    const matched = findSuggestionCandidates(
                        definitions.results.map((definition) => definition.name),
                        templates.results as HogFlowTemplate[]
                    )
                    const matchedEventNames = Array.from(new Set(matched.flatMap((candidate) => candidate.eventNames)))
                    if (matchedEventNames.length === 0) {
                        return []
                    }
                    const usedEventNames = new Set<string>()
                    await Promise.all(
                        matchedEventNames.map(async (eventName) => {
                            const response = await hogFlowsList(String(values.currentProjectId), {
                                trigger: JSON.stringify({ type: 'event', filters: { events: [{ id: eventName }] } }),
                                limit: 1,
                            })
                            if (response.count > 0) {
                                usedEventNames.add(eventName)
                            }
                        })
                    )
                    const candidates = withoutUsedEvents(matched, usedEventNames)
                    const eventNames = Array.from(new Set(candidates.flatMap((candidate) => candidate.eventNames)))
                    if (eventNames.length === 0) {
                        return []
                    }
                    const response = await api.queryHogQL<[string, number][]>(
                        hogql`SELECT event, count() FROM events WHERE timestamp >= now() - INTERVAL 7 DAY AND event IN ${eventNames} GROUP BY event`,
                        { scene: 'Workflows', productKey: 'workflows', name: 'workflows_data_suggestions' }
                    )
                    return rankSuggestions(candidates, Object.fromEntries(response.results ?? []))
                },
            },
        ],
    })),
    selectors({
        cards: [
            (s) => [s.aiResult, s.suggestions],
            (aiResult: DataSuggestionsResponseApi | null, suggestions: WorkflowSuggestion[]): SuggestionCard[] =>
                aiResult?.status === 'ready' && aiResult.suggestions.length > 0
                    ? aiResult.suggestions.map(cardFromAi)
                    : suggestions.map(cardFromRules),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        loadSuggestionsSuccess: ({ suggestions }) => {
            if (suggestions.length > 0) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows data suggestions shown', {
                    surface: props.surface,
                    source: 'rules',
                    rules: suggestions.map((suggestion) => suggestion.rule.key),
                })
            }
        },
        loadAiResultSuccess: ({ aiResult }) => {
            if (aiResult?.status === 'ready' && aiResult.suggestions.length > 0) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows data suggestions shown', {
                    surface: props.surface,
                    source: 'ai',
                    trigger_events: aiResult.suggestions.map((suggestion) => suggestion.trigger_event),
                    stages: aiResult.suggestions.map((suggestion) => suggestion.stage),
                })
            }
        },
        startSuggestion: async ({ card }) => {
            if (values.buildingKey) {
                return
            }
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows data suggestion clicked', {
                surface: props.surface,
                source: card.source,
                trigger_event: card.triggerEvent,
                weekly_count: card.weeklyCount,
                ...(card.source === 'rules' ? { rule: card.suggestion.rule.key } : { stage: card.stage }),
            })
            if (card.source === 'rules') {
                const { template, eventName } = card.suggestion
                router.actions.push(
                    urlForNewWorkflowFromTemplate(template.id, suggestionTriggerConfig(template, eventName))
                )
                return
            }
            actions.setBuildingKey(card.key)
            try {
                const projectId = String(values.currentProjectId)
                const built = await workflowDataSuggestionsBuild(projectId, { suggestion_id: card.suggestionId })
                const workflow = await hogFlowsCreate(projectId, {
                    ...(built.workflow as Record<string, unknown>),
                    status: 'draft',
                } as Parameters<typeof hogFlowsCreate>[1])
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows data suggestion built', {
                    surface: props.surface,
                    trigger_event: card.triggerEvent,
                    stage: card.stage,
                    uses_saved_template: built.uses_saved_template,
                    branded: !!built.brand_site_name,
                })
                router.actions.push(urls.workflow(workflow.id, 'workflow'))
            } catch (error: any) {
                lemonToast.error(
                    error?.detail || "We couldn't build this workflow. Try again, or start from a template."
                )
            } finally {
                actions.setBuildingKey(null)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSuggestions()
        actions.loadAiResult()
    }),
])
