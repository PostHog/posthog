export const workflowsOnboardingWizardLogic = kea<workflowsOnboardingWizardLogicType>([
    path(['products', 'workflows', 'frontend', 'setupGuide', 'wizard', 'workflowsOnboardingWizardLogic']),
    connect(() => ({
        values: [
            workflowsSetupGuideLogic,
            ['steps as guideSteps'],
            integrationsLogic,
            ['integrations'],
            workflowTemplatesLogic,
            ['workflowTemplates', 'workflowTemplatesLoading'],
        ],
        actions: [newWorkflowLogic, ['createWorkflowFromTemplate']],
    })),
    actions({
        initWizard: (path: WorkflowsOnboardingPath, step: WizardStepKey | null, templateId: string | null) => ({
            path,
            step,
            templateId,
        }),
        setStepIndex: (index: number) => ({ index }),
        next: true,
        back: true,
        selectTemplate: (templateId: string) => ({ templateId }),
        finish: true,
        exit: true,
        positionAtFirstOpenStep: (index: number) => ({ index }),
    }),
    reducers({
        wizardPath: [
            'messaging' as WorkflowsOnboardingPath,
            {
                initWizard: (_, { path }) => path,
            },
        ],
        stepIndex: [
            0,
            {
                initWizard: (_, { path, step }) => Math.max(0, step ? WIZARD_STEPS[path].indexOf(step) : 0),
                setStepIndex: (_, { index }) => index,
                positionAtFirstOpenStep: (_, { index }) => index,
            },
        ],
        selectedTemplateId: [
            null as string | null,
            {
                initWizard: (_, { templateId }) => templateId,
                selectTemplate: (_, { templateId }) => templateId,
            },
        ],
        // A person who opens the wizard fresh starts at the first open step. One who came back from a
        // sign-in, or who moved through the steps, stays where they are.
        hasPositioned: [
            false,
            {
                initWizard: (_, { step }) => step !== null,
                setStepIndex: () => true,
                positionAtFirstOpenStep: () => true,
            },
        ],
    }),
    selectors({
        stepKeys: [
            (s) => [s.wizardPath],
            (wizardPath: WorkflowsOnboardingPath): readonly WizardStepKey[] => WIZARD_STEPS[wizardPath],
        ],
        currentStep: [
            (s) => [s.stepKeys, s.stepIndex],
            (stepKeys: readonly WizardStepKey[], stepIndex: number): WizardStepKey =>
                stepKeys[Math.min(stepIndex, stepKeys.length - 1)],
        ],
        isLastStep: [
            (s) => [s.stepKeys, s.stepIndex],
            (stepKeys: readonly WizardStepKey[], stepIndex: number): boolean => stepIndex >= stepKeys.length - 1,
        ],
        templates: [
            (s) => [s.workflowTemplates, s.wizardPath],
            (workflowTemplates: HogFlowTemplate[], wizardPath: WorkflowsOnboardingPath): HogFlowTemplate[] =>
                workflowTemplates.filter((template) => matchesTemplateType(template.actions, wizardPath)),
        ],
        selectedTemplate: [
            (s) => [s.workflowTemplates, s.selectedTemplateId],
            (workflowTemplates: HogFlowTemplate[], selectedTemplateId: string | null): HogFlowTemplate | null =>
                workflowTemplates.find((template) => template.id === selectedTemplateId) ?? null,
        ],
        connectionsNeeded: [
            (s) => [s.selectedTemplate],
            (selectedTemplate: HogFlowTemplate | null): WizardConnection[] =>
                selectedTemplate ? requiredConnections(selectedTemplate.actions) : [],
        ],
        missingConnections: [
            (s) => [s.connectionsNeeded, s.integrations],
            (connectionsNeeded: WizardConnection[], integrations: IntegrationType[] | null): WizardConnection[] =>
                connectionsNeeded.filter(
                    (connection) => !integrations?.some((integration) => integration.kind === connection)
                ),
        ],
        /** Which steps are done. `null` while the messaging setup data is still loading. */
        stepDone: [
            (s) => [s.wizardPath, s.guideSteps, s.selectedTemplate, s.missingConnections],
            (
                wizardPath: WorkflowsOnboardingPath,
                guideSteps: SetupGuideStep[] | null,
                selectedTemplate: HogFlowTemplate | null,
                missingConnections: WizardConnection[]
            ): Partial<Record<WizardStepKey, boolean>> | null => {
                if (wizardPath === 'automation') {
                    return { template: !!selectedTemplate, connect: missingConnections.length === 0, create: false }
                }
                if (!guideSteps) {
                    return null
                }
                const guideDone = (key: string): boolean => guideSteps.some((step) => step.key === key && step.done)
                return {
                    channel: guideDone('channel'),
                    domain: guideDone('domain'),
                    'opt-outs': guideDone('opt-outs'),
                    journey: !!selectedTemplate,
                }
            },
        ],
        /** Why the person cannot move on from this step yet, or null when they can. */
        continueDisabledReason: [
            (s) => [s.currentStep, s.stepDone, s.selectedTemplate],
            (
                currentStep: WizardStepKey,
                stepDone: Partial<Record<WizardStepKey, boolean>> | null,
                selectedTemplate: HogFlowTemplate | null
            ): string | null => {
                if (currentStep === 'journey' || currentStep === 'template' || currentStep === 'create') {
                    return selectedTemplate ? null : 'Pick a template first'
                }
                if (WIZARD_STEP_COPY[currentStep].optional) {
                    return null
                }
                if (!stepDone) {
                    return 'Checking your setup'
                }
                return stepDone[currentStep] ? null : 'Connect an email channel first'
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        next: () => {
            const step = values.currentStep
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows onboarding wizard step completed', {
                path: values.wizardPath,
                step,
                skipped: !values.stepDone?.[step],
            })
            if (values.isLastStep) {
                actions.finish()
            } else {
                actions.setStepIndex(values.stepIndex + 1)
            }
        },
        back: () => {
            actions.setStepIndex(Math.max(0, values.stepIndex - 1))
        },
        finish: () => {
            const template = values.selectedTemplate
            if (!template) {
                return
            }
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows onboarding wizard finished', {
                path: values.wizardPath,
                template_id: template.id,
                template_scope: template.scope,
            })
            actions.createWorkflowFromTemplate(template)
        },
        exit: () => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows onboarding wizard exited', {
                path: values.wizardPath,
                step: values.currentStep,
            })
            router.actions.push(values.wizardPath === 'messaging' ? urls.workflows('channels') : urls.workflows())
        },
    })),
    subscriptions(({ actions, values }) => ({
        stepDone: (stepDone: Partial<Record<WizardStepKey, boolean>> | null) => {
            if (stepDone && !values.hasPositioned && values.wizardPath === 'messaging') {
                actions.positionAtFirstOpenStep(firstOpenStepIndex(values.stepKeys, stepDone))
            }
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.workflows(ONBOARDING_WIZARD_TAB)]: (_, searchParams) => {
            const path = searchParams.path
            if (!isOnboardingPath(path)) {
                return
            }
            const step = WIZARD_STEPS[path].includes(searchParams.step) ? (searchParams.step as WizardStepKey) : null
            const templateId = searchParams.template ? String(searchParams.template) : null
            if (path !== values.wizardPath || step !== values.currentStep || templateId !== values.selectedTemplateId) {
                actions.initWizard(path, step, templateId)
            }
        },
    })),
    // Keeps the step and the picked template in the URL, so a person who leaves to sign in to Slack
    // comes back to the same place.
    actionToUrl(({ values }) => {
        const toUrl = (): [string, Record<string, any>, Record<string, any>, { replace: boolean }] => [
            urls.workflows(ONBOARDING_WIZARD_TAB),
            {
                path: values.wizardPath,
                step: values.currentStep,
                ...(values.selectedTemplateId ? { template: values.selectedTemplateId } : {}),
            },
            router.values.hashParams,
            { replace: true },
        ]
        return {
            setStepIndex: toUrl,
            selectTemplate: toUrl,
            positionAtFirstOpenStep: toUrl,
        }
    }),
])
