import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { integrationsLogic } from 'lib/integrations/integrationsLogic'

import { hogql } from '~/queries/utils'
import { IntegrationType } from '~/types'

export type PushPlatform = 'ios' | 'android'

// Mirrors DEVICE_SUBSCRIPTION_PREFIX in nodejs/src/cdp/utils/push-subscription-utils.ts.
const DEVICE_SUBSCRIPTION_PREFIX = '$device_push_subscription_'
const DEVICE_POLL_INTERVAL_MS = 5000

const PROVIDER_FOR_PLATFORM: Record<PushPlatform, 'apns' | 'firebase'> = {
    ios: 'apns',
    android: 'firebase',
}

function pushAppId(integration: IntegrationType): string | null {
    const appId = integration.kind === 'apns' ? integration.config?.bundle_id : integration.config?.project_id
    return typeof appId === 'string' && appId ? appId : null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pushDeviceCheckLogicValues {
    integrations: IntegrationType[] | null // integrationsLogic
    appIds: string[]
    deviceRegistered: boolean
    platform: PushPlatform
    providerConnected: boolean
    providerIntegrations: IntegrationType[]
    pushIntegrations: IntegrationType[]
    registeredDeviceCount: number | null
    registeredDeviceCountLoading: boolean
    selectedPlatform: PushPlatform | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pushDeviceCheckLogicActions {
    loadIntegrationsSuccess: (
        integrations: IntegrationType[],
        payload?: any
    ) => {
        integrations: IntegrationType[]
        payload?: any
    } // integrationsLogic
    loadRegisteredDeviceCount: () => any
    loadRegisteredDeviceCountFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRegisteredDeviceCountSuccess: (
        registeredDeviceCount: number | null,
        payload?: any
    ) => {
        registeredDeviceCount: number | null
        payload?: any
    }
    setPlatform: (platform: PushPlatform) => {
        platform: PushPlatform
    }
    syncPolling: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pushDeviceCheckLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        pushIntegrations: (integrations: IntegrationType[] | null) => IntegrationType[]
        platform: (selectedPlatform: PushPlatform | null, pushIntegrations: IntegrationType[]) => PushPlatform
        providerIntegrations: (pushIntegrations: IntegrationType[], platform: PushPlatform) => IntegrationType[]
        providerConnected: (providerIntegrations: IntegrationType[]) => boolean
        appIds: (providerIntegrations: IntegrationType[]) => string[]
        deviceRegistered: (registeredDeviceCount: number | null) => boolean
    }
}

export type pushDeviceCheckLogicType = MakeLogicType<
    pushDeviceCheckLogicValues,
    pushDeviceCheckLogicActions,
    Record<string, any>,
    pushDeviceCheckLogicMeta
>

export const pushDeviceCheckLogic = kea<pushDeviceCheckLogicType>([
    path(['products', 'workflows', 'frontend', 'setupGuide', 'wizard', 'pushDeviceCheckLogic']),
    connect(() => ({
        values: [integrationsLogic, ['integrations']],
        actions: [integrationsLogic, ['loadIntegrationsSuccess']],
    })),
    actions({
        setPlatform: (platform: PushPlatform) => ({ platform }),
        syncPolling: true,
    }),
    reducers({
        selectedPlatform: [
            null as PushPlatform | null,
            {
                setPlatform: (_, { platform }) => platform,
            },
        ],
    }),
    loaders(({ values }) => ({
        registeredDeviceCount: [
            null as number | null,
            {
                loadRegisteredDeviceCount: async (): Promise<number | null> => {
                    if (!values.appIds.length) {
                        return 0
                    }
                    const prefixes = values.appIds.map((appId: string) => `${DEVICE_SUBSCRIPTION_PREFIX}${appId}`)
                    const response = await api.queryHogQL<[number][]>(
                        hogql`SELECT count() FROM persons WHERE arrayExists(key -> arrayExists(prefix -> startsWith(key, prefix), ${prefixes}), JSONExtractKeys(properties))`,
                        { productKey: 'workflows', scene: 'Workflows', name: 'push_setup_registered_devices' }
                    )
                    return response.results?.[0]?.[0] ?? 0
                },
            },
        ],
    })),
    selectors({
        pushIntegrations: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): IntegrationType[] =>
                integrations?.filter((integration) => integration.kind === 'apns' || integration.kind === 'firebase') ??
                [],
        ],
        platform: [
            (s) => [s.selectedPlatform, s.pushIntegrations],
            (selectedPlatform: PushPlatform | null, pushIntegrations: IntegrationType[]): PushPlatform =>
                selectedPlatform ??
                (pushIntegrations.some((integration) => integration.kind === 'firebase') &&
                !pushIntegrations.some((integration) => integration.kind === 'apns')
                    ? 'android'
                    : 'ios'),
        ],
        providerIntegrations: [
            (s) => [s.pushIntegrations, s.platform],
            (pushIntegrations: IntegrationType[], platform: PushPlatform): IntegrationType[] =>
                pushIntegrations.filter((integration) => integration.kind === PROVIDER_FOR_PLATFORM[platform]),
        ],
        providerConnected: [
            (s) => [s.providerIntegrations],
            (providerIntegrations: IntegrationType[]): boolean => providerIntegrations.length > 0,
        ],
        appIds: [
            (s) => [s.providerIntegrations],
            (providerIntegrations: IntegrationType[]): string[] =>
                providerIntegrations.map(pushAppId).filter((appId): appId is string => appId !== null),
        ],
        deviceRegistered: [(s) => [s.registeredDeviceCount], (count: number | null): boolean => (count ?? 0) > 0],
    }),
    listeners(({ actions, values, cache }) => ({
        syncPolling: () => {
            const shouldPoll = values.providerConnected && !values.deviceRegistered
            // Re-adding the same key restarts the poll, which would fetch again on every result.
            if (shouldPoll && !cache.devicePolling) {
                cache.devicePolling = true
                cache.disposables.add(() => {
                    actions.loadRegisteredDeviceCount()
                    const timer = window.setInterval(() => actions.loadRegisteredDeviceCount(), DEVICE_POLL_INTERVAL_MS)
                    return () => window.clearInterval(timer)
                }, 'devicePoll')
            } else if (!shouldPoll && cache.devicePolling) {
                cache.devicePolling = false
                cache.disposables.dispose('devicePoll')
            }
        },
        setPlatform: () => {
            cache.devicePolling = false
            cache.disposables.dispose('devicePoll')
            actions.loadRegisteredDeviceCountSuccess(null)
        },
        loadIntegrationsSuccess: () => actions.syncPolling(),
        loadRegisteredDeviceCountSuccess: ({ registeredDeviceCount }) => {
            if (registeredDeviceCount) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows onboarding wizard push device detected', { platform: values.platform })
            }
            actions.syncPolling()
        },
    })),
    afterMount(({ actions }) => {
        actions.syncPolling()
    }),
])
