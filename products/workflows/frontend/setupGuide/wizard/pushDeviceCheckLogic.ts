export type pushDeviceCheckLogicType = MakeLogicType<
    pushDeviceCheckLogicValues,
    pushDeviceCheckLogicActions,
    Record<string, any>,
    pushDeviceCheckLogicMeta
>

export const pushDeviceCheckLogic = kea<pushDeviceCheckLogicType>([
    path(['products', 'workflows', 'frontend', 'setupGuide', 'wizard', 'pushDeviceCheckLogic']),
    connect(() => ({
        values: [integrationsLogic, ['integrations']],
        actions: [integrationsLogic, ['loadIntegrationsSuccess']],
    })),
    actions({
        setPlatform: (platform: PushPlatform) => ({ platform }),
        syncPolling: true,
    }),
    reducers({
        selectedPlatform: [
            null as PushPlatform | null,
            {
                setPlatform: (_, { platform }) => platform,
            },
        ],
    }),
    loaders(({ values, cache }) => ({
        registeredDeviceCount: [
            null as number | null,
            {
                loadRegisteredDeviceCount: async (_ = null, breakpoint): Promise<number | null> => {
                    const appId = values.appId
                    if (!appId) {
                        return 0
                    }
                    const legacyKey = `${DEVICE_SUBSCRIPTION_PREFIX}${appId}`
                    const tags = { productKey: 'workflows', scene: 'Workflows', name: 'push_setup_registered_devices' }
                    // The default refresh mode serves a cached count for hours, so a new device would never show.
                    const refresh = { refresh: 'force_blocking' as const }
                    // Match the key or the key plus `:`, so `com.app` never counts devices of `com.app.dev`.
                    const countSubscribedPersons = async (): Promise<number> => {
                        const response = await api.queryHogQL<[number][]>(
                            hogql`SELECT count() FROM persons WHERE arrayExists(key -> key = ${legacyKey} OR startsWith(key, ${`${legacyKey}:`}), JSONExtractKeys(properties))`,
                            tags,
                            refresh
                        )
                        breakpoint()
                        return response.results?.[0]?.[0] ?? 0
                    }
                    if (cache.countedAppId !== appId) {
                        const since = dayjs().subtract(RECENT_REGISTRATION_MARGIN_MINUTES, 'minute')
                        const count = await countSubscribedPersons()
                        cache.countedAppId = appId
                        cache.recentSince = since
                        cache.checkedRegistrations = 0
                        cache.personsCheckedAt = Date.now()
                        cache.successfulChecks = 0
                        return count
                    }
                    // The person scan above found no device, so only a registration since then can change the answer.
                    const response = await api.queryHogQL<[number][]>(
                        hogql`SELECT count() FROM events WHERE event = '$set' AND timestamp >= ${cache.recentSince} AND arrayExists(key -> key = ${legacyKey} OR startsWith(key, ${`${legacyKey}:`}), JSONExtractKeys(properties.$set))`,
                        { ...tags, name: 'push_setup_recent_device_registrations' },
                        refresh
                    )
                    breakpoint()
                    const registrations = response.results?.[0]?.[0] ?? 0
                    // A person row can land after its event, so an unconfirmed registration is rechecked, at most once a minute.
                    const recheckDue =
                        registrations > 0 && Date.now() - cache.personsCheckedAt >= PERSONS_RECHECK_INTERVAL_MS
                    if (registrations <= cache.checkedRegistrations && !recheckDue) {
                        return 0
                    }
                    // A registration event stays after the device unsubscribes, so the person count decides.
                    const count = await countSubscribedPersons()
                    cache.checkedRegistrations = registrations
                    cache.personsCheckedAt = Date.now()
                    return count
                },
            },
        ],
    })),
    reducers({
        registeredDeviceCount: {
            setPlatform: () => null,
        },
    }),
    selectors({
        pushIntegrations: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): IntegrationType[] =>
                integrations?.filter((integration) => integration.kind === 'apns' || integration.kind === 'firebase') ??
                [],
        ],
        platform: [
            (s) => [s.selectedPlatform, s.pushIntegrations],
            (selectedPlatform: PushPlatform | null, pushIntegrations: IntegrationType[]): PushPlatform =>
                selectedPlatform ??
                (pushIntegrations.some((integration) => integration.kind === 'firebase') &&
                !pushIntegrations.some((integration) => integration.kind === 'apns')
                    ? 'android'
                    : 'ios'),
        ],
        providerIntegrations: [
            (s) => [s.pushIntegrations, s.platform],
            (pushIntegrations: IntegrationType[], platform: PushPlatform): IntegrationType[] =>
                pushIntegrations.filter((integration) => integration.kind === PROVIDER_FOR_PLATFORM[platform]),
        ],
        providerConnected: [
            (s) => [s.providerIntegrations],
            (providerIntegrations: IntegrationType[]): boolean => providerIntegrations.length > 0,
        ],
        appIds: [
            (s) => [s.providerIntegrations],
            (providerIntegrations: IntegrationType[]): string[] =>
                providerIntegrations.map(pushAppId).filter((appId): appId is string => appId !== null),
        ],
        // The snippet and the device check both use this one app, so a device on another app never marks it ready.
        appId: [(s) => [s.appIds], (appIds: string[]): string | null => appIds[0] ?? null],
        deviceRegistered: [(s) => [s.registeredDeviceCount], (count: number | null): boolean => (count ?? 0) > 0],
    }),
    listeners(({ actions, values, cache }) => {
        const shouldPoll = (): boolean => values.providerConnected && !values.deviceRegistered
        const scheduleNextCheck = (delayMs: number): void => {
            cache.checkScheduled = true
            cache.disposables.add(() => {
                const timer = window.setTimeout(() => {
                    cache.checkScheduled = false
                    actions.loadRegisteredDeviceCount()
                }, delayMs)
                return () => window.clearTimeout(timer)
            }, 'devicePoll')
        }
        const stopChecking = (): void => {
            cache.checkScheduled = false
            cache.disposables.dispose('devicePoll')
        }

        return {
            syncPolling: () => {
                if (!shouldPoll()) {
                    stopChecking()
                } else if (!cache.checkScheduled && !values.registeredDeviceCountLoading) {
                    actions.loadRegisteredDeviceCount()
                }
            },
            setPlatform: () => {
                stopChecking()
                cache.failedChecks = 0
                // Also supersedes a check still running for the old platform, so its count is dropped.
                actions.loadRegisteredDeviceCount()
            },
            loadIntegrationsSuccess: () => actions.syncPolling(),
            loadRegisteredDeviceCountSuccess: ({ registeredDeviceCount }) => {
                cache.failedChecks = 0
                cache.successfulChecks = (cache.successfulChecks ?? 0) + 1
                if (registeredDeviceCount) {
                    // pinned: analytics event name - renaming breaks dashboards
                    posthog.capture('workflows onboarding wizard push device detected', { platform: values.platform })
                }
                if (shouldPoll()) {
                    const step = Math.floor(cache.successfulChecks / POLLS_PER_INTERVAL_STEP)
                    scheduleNextCheck(Math.min(DEVICE_POLL_INTERVAL_MS * 2 ** step, MAX_DEVICE_POLL_INTERVAL_MS))
                } else {
                    stopChecking()
                }
            },
            loadRegisteredDeviceCountFailure: () => {
                cache.failedChecks = (cache.failedChecks ?? 0) + 1
                if (shouldPoll()) {
                    scheduleNextCheck(DEVICE_POLL_INTERVAL_MS * 2 ** Math.min(cache.failedChecks, MAX_BACKOFF_STEPS))
                }
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.syncPolling()
    }),
])
