export type WorkflowsOnboardingPath = 'messaging' | 'automation'

export interface TeamSetupGuideState {
    path: WorkflowsOnboardingPath | null
    guideHidden: boolean
    automationSuggestionDismissed: boolean
}

const EMPTY_TEAM_STATE: TeamSetupGuideState = { path: null, guideHidden: false, automationSuggestionDismissed: false }

