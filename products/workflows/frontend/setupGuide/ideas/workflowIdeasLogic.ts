export type workflowIdeasLogicType = MakeLogicType<
    workflowIdeasLogicValues,
    workflowIdeasLogicActions,
    Record<string, any>,
    workflowIdeasLogicMeta
>

export const workflowIdeasLogic = kea<workflowIdeasLogicType>([
    path(['products', 'workflows', 'frontend', 'setupGuide', 'ideas', 'workflowIdeasLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId'], integrationsLogic, ['integrations']] })),
    actions({
        applyIdea: (idea: WorkflowIdeaApi) => ({ idea }),
        dismissIdea: (idea: WorkflowIdeaApi, reason: string) => ({ idea, reason }),
        removeIdea: (id: string) => ({ id }),
        setBusyId: (id: string | null) => ({ id }),
        setSiteInput: (value: string) => ({ value }),
    }),
    loaders(({ values }) => ({
        ideas: [
            null as WorkflowIdeaApi[] | null,
            {
                loadIdeas: async (): Promise<WorkflowIdeaApi[] | null> => {
                    try {
                        return (await workflowIdeasList(String(values.currentProjectId))).results
                    } catch {
                        // Ideas are optional, so a failed call shows nothing rather than an error.
                        return []
                    }
                },
            },
        ],
    })),
    reducers({
        ideas: {
            removeIdea: (state, { id }) => state?.filter((idea) => idea.id !== id) ?? null,
        },
        busyId: [null as string | null, { setBusyId: (_, { id }) => id }],
        // One website for the whole project, so a person types it once for every card.
        siteInput: ['', { setSiteInput: (_, { value }) => value }],
    }),
    selectors({
        emailSender: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): IdeaEmailSender => ideaEmailSender(integrations),
        ],
        enteredSite: [(s) => [s.siteInput], (siteInput: string): string | null => normalizeSite(siteInput)],
    }),
    listeners(({ actions, values }) => ({
        loadIdeasSuccess: ({ ideas }) => {
            if (!ideas?.length) {
                return
            }
            void workflowIdeasViewed(String(values.currentProjectId), {
                ids: ideas.map((idea) => idea.id),
            }).catch(() => undefined)
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflow ideas shown', {
                keys: ideas.map((idea) => idea.key),
            })
        },
        applyIdea: async ({ idea }) => {
            if (values.busyId) {
                return
            }
            actions.setBusyId(idea.id)
            const projectId = String(values.currentProjectId)
            try {
                const sender = values.emailSender
                const enteredSite = idea.evidence.site_url ? null : values.enteredSite
                const withButtons = enteredSite ? withSite(idea.definition, enteredSite) : idea.definition
                const definition =
                    sender.status === 'verified' ? withEmailSender(withButtons, sender.integrationId) : withButtons
                const workflow = await hogFlowsCreate(projectId, {
                    ...definition,
                    name: idea.title,
                    description: idea.rationale,
                    status: 'draft',
                    origin_product: 'ideas',
                } as Parameters<typeof hogFlowsCreate>[1])
                await workflowIdeasAccept(projectId, idea.id, { hog_flow_id: workflow.id, site_url: enteredSite })
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflow idea used', {
                    key: idea.key,
                    sender_status: sender.status,
                    site_entered: !!enteredSite,
                })
                actions.removeIdea(idea.id)
                router.actions.push(urls.workflow(workflow.id, 'workflow'))
            } catch (error) {
                lemonToast.error(
                    error instanceof ApiError && error.detail
                        ? error.detail
                        : "We couldn't create this workflow. Try again in a moment."
                )
            } finally {
                actions.setBusyId(null)
            }
        },
        dismissIdea: async ({ idea, reason }) => {
            actions.setBusyId(idea.id)
            try {
                await workflowIdeasDismiss(String(values.currentProjectId), idea.id, { reason })
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflow idea dismissed', {
                    key: idea.key,
                    has_reason: !!reason.trim(),
                })
                actions.removeIdea(idea.id)
            } catch {
                lemonToast.error("We couldn't dismiss this idea. Try again in a moment.")
            } finally {
                actions.setBusyId(null)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadIdeas()
    }),
])
