import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import posthog from 'posthog-js'

import { NAV_PANEL_CARD_TYPE } from 'lib/components/NavPanelAdvertisement/navPanelAdShared'
import { navPanelAdvertisementLogic } from 'lib/components/NavPanelAdvertisement/NavPanelAdvertisementLogic'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import type { FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { preflightLogic } from 'lib/logic/preflightLogic'
import { teamLogic } from 'scenes/teamLogic'
import { userLogic } from 'scenes/userLogic'

import { ProductKey } from '~/queries/schema/schema-general'
import type { TeamType, UserType } from '~/types'

import type { TeamPublicType } from '../../../../frontend/src/types'
import { firstWorkflowCardVariant } from './firstWorkflowCardVariant'

// pinned: persisted dismissal key — renaming resets dismissals
export const FIRST_WORKFLOW_CARD_DISMISS_KEY = 'first-workflow'

const eventProperties = { card_type: NAV_PANEL_CARD_TYPE.FIRST_WORKFLOW, product_key: ProductKey.WORKFLOWS }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstWorkflowCardLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    hidden: boolean // navPanelAdvertisementLogic
    isCloudOrDev: boolean | undefined // preflightLogic
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    user: UserType | null // userLogic
    shouldShow: boolean
    variant: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstWorkflowCardLogicActions {
    hideAdvertisement: () => boolean // navPanelAdvertisementLogic
    reportClicked: () => {
        value: true
    }
    reportDismissed: () => {
        value: true
    }
    reportShown: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstWorkflowCardLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        variant: (
            isCloudOrDev: boolean | undefined,
            user: UserType | null,
            currentTeam: TeamPublicType | TeamType | null,
            featureFlags: FeatureFlagsSet
        ) => string | null
        shouldShow: (variant: string | null, hidden: boolean) => boolean
    }
}

export type firstWorkflowCardLogicType = MakeLogicType<
    firstWorkflowCardLogicValues,
    firstWorkflowCardLogicActions,
    Record<string, any>,
    firstWorkflowCardLogicMeta
>

export const firstWorkflowCardLogic = kea<firstWorkflowCardLogicType>([
    path(['products', 'workflows', 'frontend', 'FirstWorkflowCard', 'firstWorkflowCardLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeam'],
            featureFlagLogic,
            ['featureFlags'],
            navPanelAdvertisementLogic({ dismissKey: FIRST_WORKFLOW_CARD_DISMISS_KEY }),
            ['hidden'],
            preflightLogic,
            ['isCloudOrDev'],
            userLogic,
            ['user'],
        ],
        actions: [navPanelAdvertisementLogic({ dismissKey: FIRST_WORKFLOW_CARD_DISMISS_KEY }), ['hideAdvertisement']],
    })),
    actions({
        reportShown: true,
        reportDismissed: true,
        reportClicked: true,
    }),
    selectors({
        variant: [
            (s) => [s.isCloudOrDev, s.user, s.currentTeam, s.featureFlags],
            (
                isCloudOrDev: boolean | undefined,
                user: UserType | null,
                currentTeam: TeamType | null,
                featureFlags: FeatureFlagsSet
            ): string | null =>
                isCloudOrDev && user?.allow_sidebar_suggestions !== false
                    ? firstWorkflowCardVariant(currentTeam, featureFlags)
                    : null,
        ],
        shouldShow: [
            (s) => [s.variant, s.hidden],
            (variant: string | null, hidden: boolean): boolean => variant === 'test' && !hidden,
        ],
    }),
    listeners(() => ({
        reportShown: () => {
            posthog.capture('nav panel first workflow shown', eventProperties)
        },
        reportDismissed: () => {
            posthog.capture('nav panel first workflow dismissed', eventProperties)
        },
        reportClicked: () => {
            posthog.capture('nav panel first workflow clicked', eventProperties)
        },
    })),
])
