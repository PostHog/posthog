// pinned: persisted dismissal key and analytics values — renaming resets dismissals and breaks dashboards
export const FIRST_WORKFLOW_CARD_DISMISS_KEY = 'first-workflow'
const FIRST_WORKFLOW_CARD_SOURCE = 'nav_panel_first_workflow'

const FALLBACK_TRIGGER_EVENT = '$pageview'
const TOP_CUSTOM_EVENT_HOGQL = hogql`SELECT event FROM events WHERE timestamp > now() - INTERVAL 7 DAY AND NOT startsWith(event, '$') GROUP BY event ORDER BY count() DESC LIMIT 1`

const eventProperties = { card_type: NAV_PANEL_CARD_TYPE.FIRST_WORKFLOW, product_key: ProductKey.WORKFLOWS }

async function findTopCustomEvent(): Promise<string> {
    try {
        const response = await api.queryHogQL<[string][]>(TOP_CUSTOM_EVENT_HOGQL, {
            productKey: ProductKey.WORKFLOWS,
            name: 'first_workflow_card_top_event',
        })
        return response.results?.[0]?.[0] ?? FALLBACK_TRIGGER_EVENT
    } catch {
        return FALLBACK_TRIGGER_EVENT
    }
}

function urlForFirstWorkflow(event: string): string {
    return urlForNewWorkflowWithTrigger(
        { type: 'event', filters: { events: [{ id: event, name: event, type: 'events' }] } },
        FIRST_WORKFLOW_CARD_SOURCE
    )
}

