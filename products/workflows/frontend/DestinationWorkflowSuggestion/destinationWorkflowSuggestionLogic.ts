export type destinationWorkflowSuggestionLogicType = MakeLogicType<
    destinationWorkflowSuggestionLogicValues,
    destinationWorkflowSuggestionLogicActions,
    Record<string, any>,
    destinationWorkflowSuggestionLogicMeta
>

export const destinationWorkflowSuggestionLogic = kea<destinationWorkflowSuggestionLogicType>([
    path(['products', 'workflows', 'frontend', 'DestinationWorkflowSuggestion', 'destinationWorkflowSuggestionLogic']),
    connect(() => ({
        values: [
            userLogic,
            ['user'],
            organizationLogic,
            ['currentOrganization'],
            projectLogic,
            ['currentProjectId'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [userLogic, ['updateHasSeenProductIntroFor']],
    })),
    actions({
        openSuggestion: (template: HogFunctionTemplateType, events: string[], onContinue: () => void) => ({
            template,
            events,
            onContinue,
        }),
        toggleEvent: (event: string) => ({ event }),
        closeSuggestion: true,
        continueWithDestination: true,
        createWorkflows: true,
        openWorkflowEditor: true,
        setBuildState: (buildState: WorkflowBuildState) => ({ buildState }),
        setBuildUnavailable: true,
        rememberAnswer: true,
        resetSuggestion: true,
    }),
    reducers({
        template: [
            null as HogFunctionTemplateType | null,
            {
                openSuggestion: (_, { template }) => template,
                resetSuggestion: () => null,
            },
        ],
        events: [
            [] as string[],
            {
                openSuggestion: (_, { events }) => events,
                resetSuggestion: () => [],
            },
        ],
        selectedEvents: [
            [] as string[],
            {
                openSuggestion: (_, { events }) => events,
                toggleEvent: (state, { event }) =>
                    state.includes(event) ? state.filter((selected) => selected !== event) : [...state, event],
                resetSuggestion: () => [],
            },
        ],
        buildState: [
            null as WorkflowBuildState,
            {
                setBuildState: (_, { buildState }) => buildState,
                resetSuggestion: () => null,
            },
        ],
        // The API refuses to build, for example in privacy mode, which the frontend cannot see in advance.
        buildUnavailable: [
            false,
            {
                setBuildUnavailable: () => true,
                resetSuggestion: () => false,
            },
        ],
        // The saved answer only reaches `user` after a reload, so the save that follows "Continue" must not ask again.
        answered: [
            false,
            {
                rememberAnswer: () => true,
            },
        ],
    }),
    selectors({
        dismissed: [
            (s) => [s.user, s.answered],
            (user: UserType | null, answered: boolean): boolean =>
                answered || !!user?.has_seen_product_intro_for?.[DESTINATION_WORKFLOW_SUGGESTION_SEEN_KEY],
        ],
        shouldSuggestWorkflow: [
            (s) => [s.dismissed, s.featureFlags],
            (dismissed: boolean, featureFlags: FeatureFlagsSet) =>
                (template: HogFunctionTemplateType): boolean =>
                    !!featureFlags[FEATURE_FLAGS.WORKFLOWS_DESTINATION_SUGGESTION] &&
                    !dismissed &&
                    template.type === 'destination' &&
                    isMessagingDestinationTemplate(template.id) &&
                    !getAccessControlDisabledReason(AccessControlResourceType.Workflow, AccessControlLevel.Editor),
        ],
        // Without custom events, or without AI approval, the modal only points to Workflows instead of building them.
        canBuildWorkflows: [
            (s) => [s.events, s.currentOrganization, s.buildUnavailable],
            (events: string[], currentOrganization: OrganizationType | null, buildUnavailable: boolean): boolean =>
                events.length > 0 && !!currentOrganization?.is_ai_data_processing_approved && !buildUnavailable,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openSuggestion: ({ template, events, onContinue }) => {
            cache.onContinue = onContinue
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion shown', {
                ...templateProperties(template),
                event_count: events.length,
                variant: values.canBuildWorkflows ? 'build' : 'nudge',
            })
        },
        closeSuggestion: () => {
            if (values.buildState === 'building') {
                return
            }
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion closed', templateProperties(values.template))
            actions.resetSuggestion()
        },
        rememberAnswer: () => {
            actions.updateHasSeenProductIntroFor(DESTINATION_WORKFLOW_SUGGESTION_SEEN_KEY)
        },
        continueWithDestination: () => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion chose destination', templateProperties(values.template))
            const onContinue = cache.onContinue as (() => void) | undefined
            actions.rememberAnswer()
            actions.resetSuggestion()
            onContinue?.()
        },
        openWorkflowEditor: () => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion opened new workflow', templateProperties(values.template))
            actions.rememberAnswer()
            actions.resetSuggestion()
            router.actions.push(urls.workflowNew(), {
                [SOURCE_PREFILL_PARAM]: DESTINATION_SUGGESTION_ENTRY_SOURCE,
            })
        },
        createWorkflows: async (_, breakpoint) => {
            const template = values.template
            const events = values.selectedEvents
            if (!template || events.length === 0 || values.buildState === 'building') {
                return
            }
            const properties = { ...templateProperties(template), event_count: events.length }
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion chose workflows', properties)
            actions.setBuildState('building')
            const deadline = Date.now() + POLL_DEADLINE_MS
            try {
                const projectId = String(values.currentProjectId)
                // The first call retries a failed build for the same events. Later calls only read its status.
                let result = await workflowDataSuggestionsBuildForEvents(projectId, { events, retry: true })
                while (result.status === 'building' && Date.now() < deadline) {
                    await breakpoint(POLL_INTERVAL_MS)
                    result = await workflowDataSuggestionsBuildForEvents(projectId, { events, retry: false })
                }
                breakpoint()
                if (result.status !== 'ready' || result.workflow_ids.length === 0) {
                    throw new Error(`Build ended with status ${result.status}`)
                }
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows destination suggestion built', {
                    ...properties,
                    workflow_count: result.workflow_ids.length,
                })
                // Carries the funnel past the draft: 'workflow enabled' reads it back for each of these ids.
                result.workflow_ids.forEach((id) => saveEntrySource(id, DESTINATION_SUGGESTION_ENTRY_SOURCE))
                actions.rememberAnswer()
                actions.resetSuggestion()
                router.actions.push(
                    result.workflow_ids.length === 1
                        ? urls.workflow(result.workflow_ids[0], 'workflow')
                        : urls.workflows('workflows')
                )
            } catch (error: any) {
                if (isBreakpoint(error)) {
                    throw error
                }
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows destination suggestion build failed', {
                    ...properties,
                    status: error?.status,
                })
                if (error?.status === 403) {
                    // Retrying cannot help, so the modal offers the manual workflow instead.
                    actions.setBuildState(null)
                    actions.setBuildUnavailable()
                    return
                }
                actions.setBuildState('failed')
            }
        },
    })),
])
