import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { combineUrl, router } from 'kea-router'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { getAccessControlDisabledReason } from 'lib/utils/accessControlUtils'
import { projectLogic } from 'scenes/projectLogic'
import { urls } from 'scenes/urls'
import { userLogic } from 'scenes/userLogic'

import { AccessControlLevel, AccessControlResourceType, HogFunctionTemplateType, UserType } from '~/types'

import { saveEntrySource } from '../Broadcasts/broadcastUsage'
import { hogFlowsCreate } from '../generated/api'
import { DESTINATION_STEP_ID, buildDestinationWorkflow, isMessagingDestinationTemplate } from './destinationWorkflow'

// pinned: key into user.has_seen_product_intro_for - renaming shows the modal again to everyone who answered it
export const DESTINATION_WORKFLOW_SUGGESTION_SEEN_KEY = 'workflows_destination_suggestion'

const CREATE_FAILED_MESSAGE = "Couldn't create the workflow. Try again, or continue with the destination."

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface destinationWorkflowSuggestionLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentProjectId: number | null // projectLogic
    user: UserType | null // userLogic
    creatingWorkflow: boolean
    destinationUrl: string | null
    dismissed: boolean
    shouldSuggestWorkflow: (template: HogFunctionTemplateType) => boolean
    template: HogFunctionTemplateType | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface destinationWorkflowSuggestionLogicActions {
    updateHasSeenProductIntroFor: (
        productKey: string,
        value?: boolean | undefined
    ) => {
        productKey: string
        value: boolean
    } // userLogic
    closeSuggestion: () => {
        value: true
    }
    continueWithDestination: () => {
        value: true
    }
    createWorkflow: () => {
        value: true
    }
    openSuggestion: (
        template: HogFunctionTemplateType,
        destinationUrl: string
    ) => {
        destinationUrl: string
        template: HogFunctionTemplateType
    }
    resetSuggestion: () => {
        value: true
    }
    setCreatingWorkflow: (creatingWorkflow: boolean) => {
        creatingWorkflow: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface destinationWorkflowSuggestionLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        dismissed: (user: UserType | null) => boolean
        shouldSuggestWorkflow: (
            featureFlags: FeatureFlagsSet,
            dismissed: boolean
        ) => (template: HogFunctionTemplateType) => boolean
    }
}

export type destinationWorkflowSuggestionLogicType = MakeLogicType<
    destinationWorkflowSuggestionLogicValues,
    destinationWorkflowSuggestionLogicActions,
    Record<string, any>,
    destinationWorkflowSuggestionLogicMeta
>

export const destinationWorkflowSuggestionLogic = kea<destinationWorkflowSuggestionLogicType>([
    path(['products', 'workflows', 'frontend', 'DestinationWorkflowSuggestion', 'destinationWorkflowSuggestionLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], projectLogic, ['currentProjectId'], userLogic, ['user']],
        actions: [userLogic, ['updateHasSeenProductIntroFor']],
    })),
    actions({
        openSuggestion: (template: HogFunctionTemplateType, destinationUrl: string) => ({ template, destinationUrl }),
        closeSuggestion: true,
        continueWithDestination: true,
        createWorkflow: true,
        setCreatingWorkflow: (creatingWorkflow: boolean) => ({ creatingWorkflow }),
        resetSuggestion: true,
    }),
    reducers({
        template: [
            null as HogFunctionTemplateType | null,
            {
                openSuggestion: (_, { template }) => template,
                resetSuggestion: () => null,
            },
        ],
        destinationUrl: [
            null as string | null,
            {
                openSuggestion: (_, { destinationUrl }) => destinationUrl,
                resetSuggestion: () => null,
            },
        ],
        creatingWorkflow: [
            false,
            {
                setCreatingWorkflow: (_, { creatingWorkflow }) => creatingWorkflow,
                resetSuggestion: () => false,
            },
        ],
    }),
    selectors({
        dismissed: [
            (s) => [s.user],
            (user: UserType | null): boolean =>
                !!user?.has_seen_product_intro_for?.[DESTINATION_WORKFLOW_SUGGESTION_SEEN_KEY],
        ],
        shouldSuggestWorkflow: [
            (s) => [s.featureFlags, s.dismissed],
            (featureFlags: FeatureFlagsSet, dismissed: boolean) =>
                (template: HogFunctionTemplateType): boolean =>
                    !!featureFlags[FEATURE_FLAGS.WORKFLOWS_DESTINATION_SUGGESTION] &&
                    !dismissed &&
                    template.type === 'destination' &&
                    isMessagingDestinationTemplate(template.id) &&
                    !getAccessControlDisabledReason(AccessControlResourceType.Workflow, AccessControlLevel.Editor),
        ],
    }),
    listeners(({ actions, values }) => ({
        openSuggestion: ({ template }) => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion shown', { template_id: template.id })
        },
        closeSuggestion: () => {
            if (values.creatingWorkflow) {
                return
            }
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion closed', { template_id: values.template?.id })
            actions.resetSuggestion()
        },
        continueWithDestination: () => {
            const destinationUrl = values.destinationUrl
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion chose destination', {
                template_id: values.template?.id,
            })
            actions.updateHasSeenProductIntroFor(DESTINATION_WORKFLOW_SUGGESTION_SEEN_KEY)
            actions.resetSuggestion()
            if (destinationUrl) {
                router.actions.push(destinationUrl)
            }
        },
        createWorkflow: async () => {
            const template = values.template
            if (!template || values.creatingWorkflow) {
                return
            }
            actions.setCreatingWorkflow(true)
            try {
                const workflow = await hogFlowsCreate(
                    String(values.currentProjectId),
                    buildDestinationWorkflow(template) as unknown as Parameters<typeof hogFlowsCreate>[1]
                )
                // pinned: entry source value - 'workflow enabled' reports it, so renaming breaks the funnel
                saveEntrySource(workflow.id, 'destination_suggestion')
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows destination suggestion chose workflow', {
                    template_id: template.id,
                    workflow_id: workflow.id,
                })
                actions.updateHasSeenProductIntroFor(DESTINATION_WORKFLOW_SUGGESTION_SEEN_KEY)
                actions.resetSuggestion()
                router.actions.push(
                    combineUrl(urls.workflow(workflow.id, 'workflow'), { node: DESTINATION_STEP_ID }).url
                )
            } catch (error: any) {
                lemonToast.error(error?.detail || CREATE_FAILED_MESSAGE)
                actions.setCreatingWorkflow(false)
            }
        },
    })),
])
