import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { getAccessControlDisabledReason } from 'lib/utils/accessControlUtils'
import { urls } from 'scenes/urls'
import { userLogic } from 'scenes/userLogic'

import { AccessControlLevel, AccessControlResourceType, HogFunctionTemplateType, UserType } from '~/types'

import { isMessagingDestinationTemplate } from './messagingDestinations'

// pinned: key into user.has_seen_product_intro_for - renaming shows the modal again to everyone who answered it
export const DESTINATION_WORKFLOW_SUGGESTION_SEEN_KEY = 'workflows_destination_suggestion'

// pinned: event properties - the funnel from shown to opened workflows breaks down on these
function templateProperties(template: HogFunctionTemplateType | null): Record<string, string | undefined> {
    return { template_id: template?.id, template_name: template?.name }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface destinationWorkflowSuggestionLogicValues {
    user: UserType | null // userLogic
    destinationUrl: string | null
    dismissed: boolean
    shouldSuggestWorkflow: (template: HogFunctionTemplateType) => boolean
    template: HogFunctionTemplateType | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface destinationWorkflowSuggestionLogicActions {
    updateHasSeenProductIntroFor: (
        productKey: string,
        value?: boolean | undefined
    ) => {
        productKey: string
        value: boolean
    } // userLogic
    closeSuggestion: () => {
        value: true
    }
    continueWithDestination: () => {
        value: true
    }
    openSuggestion: (
        template: HogFunctionTemplateType,
        destinationUrl: string
    ) => {
        destinationUrl: string
        template: HogFunctionTemplateType
    }
    openWorkflows: () => {
        value: true
    }
    resetSuggestion: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface destinationWorkflowSuggestionLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        dismissed: (user: UserType | null) => boolean
        shouldSuggestWorkflow: (dismissed: boolean) => (template: HogFunctionTemplateType) => boolean
    }
}

export type destinationWorkflowSuggestionLogicType = MakeLogicType<
    destinationWorkflowSuggestionLogicValues,
    destinationWorkflowSuggestionLogicActions,
    Record<string, any>,
    destinationWorkflowSuggestionLogicMeta
>

export const destinationWorkflowSuggestionLogic = kea<destinationWorkflowSuggestionLogicType>([
    path(['products', 'workflows', 'frontend', 'DestinationWorkflowSuggestion', 'destinationWorkflowSuggestionLogic']),
    connect(() => ({
        values: [userLogic, ['user']],
        actions: [userLogic, ['updateHasSeenProductIntroFor']],
    })),
    actions({
        openSuggestion: (template: HogFunctionTemplateType, destinationUrl: string) => ({ template, destinationUrl }),
        closeSuggestion: true,
        continueWithDestination: true,
        openWorkflows: true,
        resetSuggestion: true,
    }),
    reducers({
        template: [
            null as HogFunctionTemplateType | null,
            {
                openSuggestion: (_, { template }) => template,
                resetSuggestion: () => null,
            },
        ],
        destinationUrl: [
            null as string | null,
            {
                openSuggestion: (_, { destinationUrl }) => destinationUrl,
                resetSuggestion: () => null,
            },
        ],
    }),
    selectors({
        dismissed: [
            (s) => [s.user],
            (user: UserType | null): boolean =>
                !!user?.has_seen_product_intro_for?.[DESTINATION_WORKFLOW_SUGGESTION_SEEN_KEY],
        ],
        shouldSuggestWorkflow: [
            (s) => [s.dismissed],
            (dismissed: boolean) =>
                (template: HogFunctionTemplateType): boolean =>
                    !dismissed &&
                    template.type === 'destination' &&
                    isMessagingDestinationTemplate(template.id) &&
                    !getAccessControlDisabledReason(AccessControlResourceType.Workflow, AccessControlLevel.Editor),
        ],
    }),
    listeners(({ actions, values }) => ({
        openSuggestion: ({ template }) => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion shown', templateProperties(template))
        },
        closeSuggestion: () => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion closed', templateProperties(values.template))
            actions.resetSuggestion()
        },
        continueWithDestination: () => {
            const destinationUrl = values.destinationUrl
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion chose destination', templateProperties(values.template))
            actions.updateHasSeenProductIntroFor(DESTINATION_WORKFLOW_SUGGESTION_SEEN_KEY)
            actions.resetSuggestion()
            if (destinationUrl) {
                router.actions.push(destinationUrl)
            }
        },
        openWorkflows: () => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows destination suggestion opened workflows', templateProperties(values.template))
            actions.updateHasSeenProductIntroFor(DESTINATION_WORKFLOW_SUGGESTION_SEEN_KEY)
            actions.resetSuggestion()
            router.actions.push(urls.workflows('templates'))
        },
    })),
])
