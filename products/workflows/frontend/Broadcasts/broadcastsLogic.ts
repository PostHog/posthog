import {
    hogFlowsBatchJobsList,
    hogFlowsCreate,
    hogFlowsDestroy,
    hogFlowsList,
    hogFlowsPartialUpdate,
    hogFlowsRetrieve,
} from 'products/workflows/frontend/generated/api'
