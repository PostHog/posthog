/**
 * Backs the review step's email preview: loads a sample of the audience, then renders the email
 * against whichever person is picked.
 */
export const broadcastPreviewLogic = kea<broadcastPreviewLogicType>([
    path(['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastPreviewLogic']),
    props({} as BroadcastWizardLogicProps),
    key((props) => props.id),

    connect((props: BroadcastWizardLogicProps) => ({
        values: [broadcastWizardLogic(props), ['audienceProperties', 'email']],
    })),

    actions({
        selectPerson: (personId: string | null) => ({ personId }),
    }),

    loaders(({ values }) => ({
        persons: [
            [] as BroadcastPreviewPerson[],
            {
                loadPersons: async () => {
                    const query: ActorsQuery = {
                        kind: NodeKind.ActorsQuery,
                        // The recipients step only offers person-scoped filters, which is all an
                        // actors query accepts.
                        properties: values.audienceProperties as AnyPersonScopeFilter[],
                        select: ['id', 'person_display_name -- Person', 'properties'],
                        limit: PREVIEW_PERSON_LIMIT,
                    }
                    const response = await api.query<ActorsQuery>(query)
                    return (response.results ?? []).map(parsePerson)
                },
            },
        ],
    })),

    reducers({
        selectedPersonId: [
            null as string | null,
            {
                selectPerson: (_, { personId }) => personId,
                // The audience decides who is on offer, so a reload invalidates the old pick.
                loadPersons: () => null,
            },
        ],
    }),

    selectors({
        previewPerson: [
            (s) => [s.persons, s.selectedPersonId],
            (persons: BroadcastPreviewPerson[], selectedPersonId: string | null): BroadcastPreviewPerson | null =>
                persons.find((person) => person.id === selectedPersonId) ?? persons[0] ?? null,
        ],
        previewSubject: [
            (s) => [s.email, s.previewPerson],
            (email: BroadcastEmailValue, previewPerson: BroadcastPreviewPerson | null): string =>
                renderEmailPreview(email.subject, previewPerson),
        ],
        previewHtml: [
            (s) => [s.email, s.previewPerson],
            (email: BroadcastEmailValue, previewPerson: BroadcastPreviewPerson | null): string =>
                renderEmailPreview(email.html, previewPerson),
        ],
        previewTo: [
            (s) => [s.email, s.previewPerson],
            (email: BroadcastEmailValue, previewPerson: BroadcastPreviewPerson | null): string =>
                renderEmailPreview(email.to?.email ?? '', previewPerson),
        ],
    }),

    // Reload on the value rather than on the edit action, so resuming a saved draft loads against
    // the audience it hydrates with instead of the empty one the logic mounted on.
    subscriptions(({ actions }) => ({
        audienceProperties: () => {
            actions.loadPersons()
        },
    })),
])
