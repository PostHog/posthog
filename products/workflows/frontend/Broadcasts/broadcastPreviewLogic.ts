/** How many of the audience to offer in the picker. Enough to find a representative person. */
const PREVIEW_PERSON_LIMIT = 25

export interface BroadcastPreviewPerson extends EmailPreviewPerson {
    displayName: string
}

// The properties column arrives as a JSON string over the query API, but tolerate an object in case
// a caller hands one over already parsed.
function parseProperties(raw: unknown): Record<string, any> {
    if (raw && typeof raw === 'object') {
        return raw as Record<string, any>
    }
    if (typeof raw === 'string') {
        try {
            return JSON.parse(raw)
        } catch {
            return {}
        }
    }
    return {}
}

function parsePerson(row: any[]): BroadcastPreviewPerson {
    const properties = parseProperties(row[2])
    return {
        id: String(row[0]),
        displayName: row[1]?.display_name || properties.email || String(row[0]),
        properties,
    }
}

