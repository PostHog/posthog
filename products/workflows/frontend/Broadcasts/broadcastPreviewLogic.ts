export const broadcastPreviewScope = (broadcastId: string): string => `broadcast-${broadcastId}`

export type broadcastPreviewLogicType = MakeLogicType<
    broadcastPreviewLogicValues,
    broadcastPreviewLogicActions,
    BroadcastWizardLogicProps,
    broadcastPreviewLogicMeta
>

export const broadcastPreviewLogic = kea<broadcastPreviewLogicType>([
    path(['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastPreviewLogic']),
    props({} as BroadcastWizardLogicProps),
    key((props) => props.id),

    connect((props: BroadcastWizardLogicProps) => ({
        values: [
            broadcastWizardLogic(props),
            ['audienceProperties', 'email', 'push'],
            emailPreviewPersonLogic({ scope: broadcastPreviewScope(props.id) }),
            ['persons', 'personsLoading', 'personsFailed', 'selectedPersonId', 'previewPerson'],
        ],
        actions: [
            emailPreviewPersonLogic({ scope: broadcastPreviewScope(props.id) }),
            ['loadPersons', 'loadPersonsSuccess', 'loadPersonsFailure', 'selectPerson', 'setAudience'],
        ],
    })),

    selectors({
        previewSubject: [
            (s) => [s.email, s.previewPerson],
            (email: BroadcastEmailValue, previewPerson: PreviewPerson | null): string =>
                renderEmailPreview(email.subject, previewPerson),
        ],
        previewHtml: [
            (s) => [s.email, s.previewPerson],
            (email: BroadcastEmailValue, previewPerson: PreviewPerson | null): string =>
                renderEmailPreview(email.html, previewPerson),
        ],
        // The worker renders liquid in every string of the email input, `text` included, so a
        // text-only broadcast has to preview through the same renderer as the html one.
        previewText: [
            (s) => [s.email, s.previewPerson],
            (email: BroadcastEmailValue, previewPerson: PreviewPerson | null): string =>
                renderEmailPreview(email.text, previewPerson),
        ],
        previewPushTitle: [
            (s) => [s.push, s.previewPerson],
            (push: BroadcastPushValue, previewPerson: PreviewPerson | null): string =>
                renderEmailPreview(push.title, previewPerson),
        ],
        previewPushBody: [
            (s) => [s.push, s.previewPerson],
            (push: BroadcastPushValue, previewPerson: PreviewPerson | null): string =>
                renderEmailPreview(push.body, previewPerson),
        ],
        previewTo: [
            (s) => [s.email, s.previewPerson],
            (email: BroadcastEmailValue, previewPerson: PreviewPerson | null): string =>
                renderEmailPreview(email.to?.email ?? '', previewPerson),
        ],
    }),

    // Reload on the value rather than on the edit action, so resuming a saved draft loads against
    // the audience it hydrates with instead of the empty one the logic mounted on.
    subscriptions(({ actions }) => ({
        audienceProperties: (audienceProperties: AnyPropertyFilter[]) => {
            actions.setAudience(toActorsQueryProperties(audienceProperties))
        },
    })),
])
