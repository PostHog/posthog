export const broadcastSentLogic = kea<broadcastSentLogicType>([
    path(['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastSentLogic']),
    props({} as BroadcastSentLogicProps),
    key((props) => `${props.id}-${props.parentRunId ?? 'none'}`),

    actions({
        setStatusFilter: (status: string | null) => ({ status }),
        selectInvocation: (invocationId: string | null) => ({ invocationId }),
        setRecipientSearch: (search: string) => ({ search }),
        setHasMoreRecipients: (hasMore: boolean) => ({ hasMore }),
    }),

    loaders(({ props, values, actions, cache }) => {
        const loadPage = async (query: SendsQuery, offset: number): Promise<MessageAsset[]> => {
            if (!props.id || props.id === 'new' || !props.parentRunId) {
                return []
            }
            // Scoped to the run rather than the flow: a recurring broadcast has one set of
            // sends per run, and mixing them would double-count a recipient.
            const page = await getMessageAssets(props.id, {
                parent_run_id: props.parentRunId,
                // Searched and filtered on the server: a run can reach far more people than one page
                // holds, so filtering the loaded pages would cover only the first slice of them.
                search: query.search || undefined,
                status: query.status || undefined,
                limit: SENT_ROW_LIMIT,
                offset,
            })
            return page
        }
        return {
            sends: [
                [] as MessageAsset[],
                {
                    loadSends: async (_: void, breakpoint) => {
                        cache.queryVersion = (cache.queryVersion ?? 0) + 1
                        const version = cache.queryVersion
                        const query = { search: values.recipientSearch, status: values.statusFilter }
                        let page: MessageAsset[]
                        try {
                            page = await loadPage(query, 0)
                        } catch (error) {
                            // A newer search has started, so this failure no longer describes what is shown.
                            breakpoint()
                            throw error
                        }
                        // Drops a response that lands after a newer search or filter started.
                        breakpoint()
                        cache.loadedQuery = query
                        cache.loadedVersion = version
                        cache.nextOffset = page.length
                        actions.setHasMoreRecipients(page.length >= SENT_ROW_LIMIT)
                        return page
                    },
                    // Pages the query the shown rows came from, so a search typed since cannot be
                    // appended at an offset that belongs to the previous results. A page that lands
                    // after a newer query started is dropped rather than written over its results.
                    loadMoreSends: async () => {
                        const version = cache.queryVersion
                        // The first page of a newer query has not landed yet, so the shown rows and the
                        // offset still belong to the old query. Any load-more success clears the shared
                        // loading flag, so the button can be clicked in this window.
                        if (cache.loadedVersion !== version) {
                            return values.sends
                        }
                        const shown = values.sends
                        const offset: number = cache.nextOffset ?? shown.length
                        const page = await loadPage(cache.loadedQuery ?? { search: '', status: null }, offset)
                        if (version !== cache.queryVersion) {
                            return values.sends
                        }
                        cache.nextOffset = offset + page.length
                        actions.setHasMoreRecipients(page.length >= SENT_ROW_LIMIT)
                        // A run that is still sending adds rows at the top, which pushes rows from the end
                        // of the shown pages onto this one. Dropping them keeps each recipient listed once.
                        // The offset counts every row the server returned, so it moves past the repeats
                        // instead of fetching them again.
                        const shownKeys = new Set(shown.map((send) => `${send.invocation_id}:${send.action_id}`))
                        return [
                            ...shown,
                            ...page.filter((send) => !shownKeys.has(`${send.invocation_id}:${send.action_id}`)),
                        ]
                    },
                },
            ],
        }
    }),

    reducers({
        // An empty list and a failed request both render as no rows, but they mean different things
        // to someone checking whether a send reached anyone.
        sendsFailed: [
            false,
            {
                loadSends: () => false,
                loadSendsSuccess: () => false,
                loadSendsFailure: () => true,
            },
        ],
        statusFilter: [
            null as string | null,
            {
                setStatusFilter: (_, { status }) => status,
            },
        ],
        selectedInvocationId: [
            null as string | null,
            {
                selectInvocation: (_, { invocationId }) => invocationId,
                loadSends: () => null,
            },
        ],
        hasMoreRecipients: [
            false,
            {
                setHasMoreRecipients: (_, { hasMore }) => hasMore,
            },
        ],
        recipientSearch: [
            '',
            {
                setRecipientSearch: (_, { search }) => search,
            },
        ],
    }),

    listeners(({ actions }) => ({
        setRecipientSearch: async (_, breakpoint) => {
            await breakpoint(300)
            actions.loadSends()
        },
        setStatusFilter: () => {
            actions.loadSends()
        },
    })),

    selectors({
        selectedSend: [
            (s) => [s.sends, s.selectedInvocationId],
            (sends: MessageAsset[], selectedInvocationId: string | null): MessageAsset | null =>
                sends.find((send) => send.invocation_id === selectedInvocationId) ?? null,
        ],
        recipientCount: [(s) => [s.sends], (sends: MessageAsset[]): number => sends.length],
        // An empty list for an older run can mean its sends expired, not that it reached nobody.
        runPastRetention: [
            (_, p) => [p.runCreatedAt],
            (runCreatedAt: string | null): boolean =>
                !!runCreatedAt && dayjs().diff(dayjs(runCreatedAt), 'day') >= SEND_RETENTION_DAYS,
        ],
    }),
])
