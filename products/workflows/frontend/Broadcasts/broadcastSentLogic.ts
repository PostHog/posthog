export type broadcastSentLogicType = MakeLogicType<
    broadcastSentLogicValues,
    broadcastSentLogicActions,
    BroadcastWizardLogicProps
>

export const broadcastSentLogic = kea<broadcastSentLogicType>([
    path(['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastSentLogic']),
    props({} as BroadcastWizardLogicProps),
    key((props) => props.id),

    actions({
        setStatusFilter: (status: BroadcastSendStatus | null) => ({ status }),
        selectRecipient: (recipient: string | null) => ({ recipient }),
    }),

    loaders(({ props }) => ({
        sends: [
            [] as BroadcastSendRow[],
            {
                loadSends: async () => {
                    if (!props.id || props.id === 'new') {
                        return []
                    }
                    // One row per recipient rather than one per event: the tab answers "who got this
                    // and how far did they get", which a raw event list makes the reader assemble.
                    const query: HogQLQuery = {
                        kind: NodeKind.HogQLQuery,
                        query: `
                            SELECT
                                properties.$email_to AS recipient,
                                any(properties.$email_subject) AS subject,
                                max(timestamp) AS last_event_at,
                                arrayDistinct(groupArray(event)) AS events,
                                any(person.properties) AS person_properties
                            FROM events
                            WHERE properties.$workflow_id = {broadcastId}
                              AND event IN {trackedEvents}
                              AND notEmpty(toString(properties.$email_to))
                            GROUP BY recipient
                            ORDER BY last_event_at DESC
                            LIMIT ${SENT_ROW_LIMIT}
                        `,
                        values: { broadcastId: props.id, trackedEvents: TRACKED_EVENTS },
                    }
                    const response = await api.query<HogQLQuery>(query)
                    return (response.results ?? []).map(parseRow)
                },
            },
        ],
    })),

    reducers({
        // An empty list and a failed query both render as no rows, but they mean different things
        // to someone checking whether a send reached anyone.
        sendsFailed: [
            false,
            {
                loadSends: () => false,
                loadSendsSuccess: () => false,
                loadSendsFailure: () => true,
            },
        ],
        statusFilter: [
            null as BroadcastSendStatus | null,
            {
                setStatusFilter: (_, { status }) => status,
            },
        ],
        selectedRecipient: [
            null as string | null,
            {
                selectRecipient: (_, { recipient }) => recipient,
                loadSends: () => null,
            },
        ],
    }),

    selectors({
        filteredSends: [
            (s) => [s.sends, s.statusFilter],
            (sends: BroadcastSendRow[], statusFilter: BroadcastSendStatus | null): BroadcastSendRow[] =>
                statusFilter ? sends.filter((send) => send.status === statusFilter) : sends,
        ],
        selectedSend: [
            (s) => [s.sends, s.selectedRecipient],
            (sends: BroadcastSendRow[], selectedRecipient: string | null): BroadcastSendRow | null =>
                sends.find((send) => send.recipient === selectedRecipient) ?? null,
        ],
    }),
])
