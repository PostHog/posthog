import { MakeLogicType, actions, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { dayjs } from 'lib/dayjs'

import { MessageAsset, getMessageAssets } from '../Workflows/messageAssetsApi'
import { BroadcastWizardLogicProps } from './broadcastWizardLogic'

/** How many recipients a page holds. A run can reach far more, so further pages load on request. */
const SENT_ROW_LIMIT = 500

/** Matches MESSAGE_ASSETS_TTL_DAYS: ClickHouse deletes a send this many days after it went out. */
const SEND_RETENTION_DAYS = 30

interface SendsQuery {
    search: string
    status: string | null
}

/** The statuses a send can end in, offered whether or not the loaded pages contain them. */
export const SEND_STATUSES = ['sent', 'delivered', 'opened', 'clicked', 'bounced', 'failed', 'unsubscribed', 'spam']

export interface BroadcastSentLogicProps extends BroadcastWizardLogicProps {
    /** The batch run whose sends to list. Every send of a broadcast belongs to one. */
    parentRunId: string | null
    /** When the run started. Its sends go out at or after this time. */
    runCreatedAt: string | null
}

