import { MakeLogicType, actions, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'

import { HogQLQuery, NodeKind } from '~/queries/schema/schema-general'

import { BroadcastWizardLogicProps } from './broadcastWizardLogic'

/** How many recipients the tab lists. A broadcast can reach far more; this is a readable sample. */
const SENT_ROW_LIMIT = 500

export type BroadcastSendStatus =
    | 'sent'
    | 'delivered'
    | 'opened'
    | 'clicked'
    | 'bounced'
    | 'failed'
    | 'unsubscribed'
    | 'spam'

export interface BroadcastSendRow {
    recipient: string
    subject: string
    lastEventAt: string
    status: BroadcastSendStatus
    /** The recipient's person properties, so the email can be re-rendered exactly as they saw it. */
    personProperties: Record<string, any>
}

// The engagement events a send produces, most engaged last: a recipient's status is the furthest
// they got, so a click outranks an open which outranks a delivery.
const PROGRESS_EVENTS: [string, BroadcastSendStatus][] = [
    ['$workflows_email_sent', 'sent'],
    ['$workflows_email_delivered', 'delivered'],
    ['$workflows_email_opened', 'opened'],
    ['$workflows_email_link_clicked', 'clicked'],
]

// Terminal outcomes win over progress regardless of order: a bounce after a delivery is still a
// bounce, and showing it as "delivered" would hide the failure.
const TERMINAL_EVENTS: [string, BroadcastSendStatus][] = [
    ['$workflows_email_unsubscribed', 'unsubscribed'],
    ['$workflows_email_marked_as_spam', 'spam'],
    ['$workflows_email_bounced', 'bounced'],
    ['$workflows_email_failed', 'failed'],
]

const TRACKED_EVENTS = [...PROGRESS_EVENTS, ...TERMINAL_EVENTS].map(([event]) => event)

function statusFromEvents(events: string[]): BroadcastSendStatus {
    for (const [event, status] of TERMINAL_EVENTS) {
        if (events.includes(event)) {
            return status
        }
    }
    let status: BroadcastSendStatus = 'sent'
    for (const [event, candidate] of PROGRESS_EVENTS) {
        if (events.includes(event)) {
            status = candidate
        }
    }
    return status
}

// The properties column arrives as a JSON string over the query API, but tolerate an object.
function parseProperties(raw: unknown): Record<string, any> {
    if (raw && typeof raw === 'object') {
        return raw as Record<string, any>
    }
    if (typeof raw === 'string') {
        try {
            return JSON.parse(raw)
        } catch {
            return {}
        }
    }
    return {}
}

function parseRow(row: any[]): BroadcastSendRow {
    const events = Array.isArray(row[3]) ? row[3].map(String) : []
    return {
        recipient: String(row[0] ?? ''),
        subject: String(row[1] ?? ''),
        lastEventAt: String(row[2] ?? ''),
        status: statusFromEvents(events),
        personProperties: parseProperties(row[4]),
    }
}

