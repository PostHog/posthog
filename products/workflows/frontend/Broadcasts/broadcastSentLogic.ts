import { MakeLogicType, actions, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { MessageAsset, getMessageAssets } from '../Workflows/messageAssetsApi'
import { BroadcastWizardLogicProps } from './broadcastWizardLogic'

/** How many recipients the tab lists. A broadcast can reach far more; this is a readable page. */
const SENT_ROW_LIMIT = 500

export interface BroadcastSentLogicProps extends BroadcastWizardLogicProps {
    /** The batch run whose sends to list. Every send of a broadcast belongs to one. */
    parentRunId: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface broadcastSentLogicValues {
    sends: MessageAsset[]
    sendsLoading: boolean
    sendsFailed: boolean
    statusFilter: string | null
    statuses: string[]
    filteredSends: MessageAsset[]
    selectedInvocationId: string | null
    selectedSend: MessageAsset | null
    previewSend: MessageAsset | null
    recipientCount: number
    recipientSearch: string
    hasMoreRecipients: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface broadcastSentLogicActions {
    loadSends: () => {
        value: true
    }
    loadSendsSuccess: (
        sends: MessageAsset[],
        payload?: {
            value: true
        }
    ) => {
        sends: MessageAsset[]
        payload?: {
            value: true
        }
    }
    loadSendsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    setStatusFilter: (status: string | null) => {
        status: string | null
    }
    selectInvocation: (invocationId: string | null) => {
        invocationId: string | null
    }
    setPreviewSend: (send: MessageAsset | null) => {
        send: MessageAsset | null
    }
    setRecipientSearch: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface broadcastSentLogicMeta {
    actions: broadcastSentLogicActions
    values: broadcastSentLogicValues
    selectors: {
        sends: (state: any, props: any) => MessageAsset[]
        sendsLoading: (state: any, props: any) => boolean
        sendsFailed: (state: any, props: any) => boolean
        statusFilter: (state: any, props: any) => string | null
        selectedInvocationId: (state: any, props: any) => string | null
        statuses: (sends: MessageAsset[]) => string[]
        filteredSends: (sends: MessageAsset[], statusFilter: string | null) => MessageAsset[]
        selectedSend: (sends: MessageAsset[], selectedInvocationId: string | null) => MessageAsset | null
        previewSend: (state: any, props: any) => MessageAsset | null
        recipientCount: (sends: MessageAsset[]) => number
        recipientSearch: (state: any, props: any) => string
        hasMoreRecipients: (sends: MessageAsset[]) => boolean
    }
}

export type broadcastSentLogicType = MakeLogicType<
    broadcastSentLogicValues,
    broadcastSentLogicActions,
    BroadcastSentLogicProps
>

export const broadcastSentLogic = kea<broadcastSentLogicType>([
    path(['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastSentLogic']),
    props({} as BroadcastSentLogicProps),
    key((props) => `${props.id}-${props.parentRunId ?? 'none'}`),

    actions({
        setStatusFilter: (status: string | null) => ({ status }),
        selectInvocation: (invocationId: string | null) => ({ invocationId }),
        setPreviewSend: (send: MessageAsset | null) => ({ send }),
        setRecipientSearch: (search: string) => ({ search }),
    }),

    loaders(({ props, values }) => ({
        sends: [
            [] as MessageAsset[],
            {
                loadSends: async () => {
                    if (!props.id || props.id === 'new' || !props.parentRunId) {
                        return []
                    }
                    // Scoped to the run rather than the flow: a recurring broadcast has one set of
                    // sends per run, and mixing them would double-count a recipient.
                    return await getMessageAssets(props.id, {
                        parent_run_id: props.parentRunId,
                        // Searched on the server: a broadcast can reach far more people than one page
                        // holds, so filtering the loaded page would search only the first slice of them.
                        search: values.recipientSearch || undefined,
                        limit: SENT_ROW_LIMIT,
                    })
                },
            },
        ],
    })),

    reducers({
        // An empty list and a failed request both render as no rows, but they mean different things
        // to someone checking whether a send reached anyone.
        sendsFailed: [
            false,
            {
                loadSends: () => false,
                loadSendsSuccess: () => false,
                loadSendsFailure: () => true,
            },
        ],
        statusFilter: [
            null as string | null,
            {
                setStatusFilter: (_, { status }) => status,
                loadSends: () => null,
            },
        ],
        selectedInvocationId: [
            null as string | null,
            {
                selectInvocation: (_, { invocationId }) => invocationId,
                loadSends: () => null,
            },
        ],
        // Separate from selectedInvocationId: this one drives the inline Content preview, which opens on
        // a real recipient, while selectedInvocationId opens the modal and must stay closed until clicked.
        recipientSearch: [
            '',
            {
                setRecipientSearch: (_, { search }) => search,
            },
        ],
        // Holds the asset itself, not an id into `sends`: a search narrows that list, and a preview
        // looked up inside it would fall back to the raw template the moment the previewed person
        // dropped out of the current page. Separate from selectedInvocationId, which opens the modal.
        previewSend: [
            null as MessageAsset | null,
            {
                setPreviewSend: (_, { send }) => send,
                // Only fills the empty default, so a later search never moves the preview on its own.
                loadSendsSuccess: (state, { sends }) => state ?? sends[0] ?? null,
            },
        ],
    }),

    listeners(({ actions }) => ({
        setRecipientSearch: async (_, breakpoint) => {
            await breakpoint(300)
            actions.loadSends()
        },
    })),

    selectors({
        // Offered from what this run actually produced, so the filter never lists a status with no rows.
        statuses: [
            (s) => [s.sends],
            (sends: MessageAsset[]): string[] =>
                Array.from(new Set(sends.map((send) => send.status).filter(Boolean))).sort(),
        ],
        filteredSends: [
            (s) => [s.sends, s.statusFilter],
            (sends: MessageAsset[], statusFilter: string | null): MessageAsset[] =>
                statusFilter ? sends.filter((send) => send.status === statusFilter) : sends,
        ],
        selectedSend: [
            (s) => [s.sends, s.selectedInvocationId],
            (sends: MessageAsset[], selectedInvocationId: string | null): MessageAsset | null =>
                sends.find((send) => send.invocation_id === selectedInvocationId) ?? null,
        ],
        recipientCount: [(s) => [s.sends], (sends: MessageAsset[]): number => sends.length],
        // The API caps a page, so a full page means there are more we haven't counted.
        hasMoreRecipients: [(s) => [s.sends], (sends: MessageAsset[]): boolean => sends.length >= SENT_ROW_LIMIT],
    }),
])
