export type broadcastSendingLogicType = MakeLogicType<
    broadcastSendingLogicValues,
    broadcastSendingLogicActions,
    BroadcastWizardLogicProps,
    broadcastSendingLogicMeta
>

/** The live send state on a broadcast's summary: what is still queued, and an email pause. */
export const broadcastSendingLogic = kea<broadcastSendingLogicType>([
    path((id) => ['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastSendingLogic', id]),
    props({} as BroadcastWizardLogicProps),
    key((props) => props.id),
    connect((props: BroadcastWizardLogicProps) => ({
        values: [projectLogic, ['currentProjectId'], broadcastWizardLogic(props), ['broadcast']],
        actions: [broadcastWizardLogic(props), ['loadBroadcast']],
    })),

    actions({
        resumeEmailSending: true,
        confirmResumeEmailSending: true,
        setResumingEmailSending: (resuming: boolean) => ({ resuming }),
    }),

    loaders(({ values, props }) => ({
        inFlight: [
            null as HogFlowInFlightApi | null,
            {
                loadInFlight: async () => {
                    if (props.id === 'new' || !values.currentProjectId) {
                        return null
                    }
                    return await hogFlowsInFlightRetrieve(String(values.currentProjectId), props.id)
                },
            },
        ],
    })),

    reducers({
        inFlightFailed: [false, { loadInFlight: () => false, loadInFlightFailure: () => true }],
        resumingEmailSending: [false, { setResumingEmailSending: (_, { resuming }) => resuming }],
    }),

    selectors({
        stillToSend: [
            (s) => [s.inFlight],
            (inFlight: HogFlowInFlightApi | null): number | null => inFlight?.count ?? null,
        ],
        emailSendingPause: [
            (s) => [s.broadcast],
            (broadcast: HogFlowApi | null): EmailSendingPause => emailSendingPause(broadcast),
        ],
    }),

    listeners(({ actions, values, props }) => ({
        resumeEmailSending: () => {
            if (values.resumingEmailSending) {
                return
            }
            openResumeEmailSendingDialog('broadcast', () => actions.confirmResumeEmailSending())
        },
        confirmResumeEmailSending: async () => {
            // Also guards the dialog's close animation, where a fast double-click dispatches twice.
            if (values.resumingEmailSending || !values.currentProjectId) {
                return
            }
            actions.setResumingEmailSending(true)
            try {
                await requestResumeEmailSending(String(values.currentProjectId), props.id)
            } finally {
                actions.setResumingEmailSending(false)
                // Reload either way: on success to clear the banner, on failure because someone else may have resumed it.
                actions.loadBroadcast()
            }
        },
    })),

    afterMount(({ actions, values, cache }) => {
        actions.loadInFlight()
        // A send in progress drains the queue and can be paused for bounces, so both are re-read while it runs.
        cache.disposables.add(() => {
            const id = window.setInterval(() => {
                if (values.stillToSend === 0) {
                    return
                }
                actions.loadInFlight()
                actions.loadBroadcast()
            }, SENDING_REFRESH_INTERVAL_MS)
            return () => clearInterval(id)
        }, 'sendingRefresh')
    }),
])
