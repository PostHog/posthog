// Fixed id for the single email action in the synthetic test flow. The edges below reference it,
// and it goes over as `current_action_id` so the worker runs just this node.
const TEST_EMAIL_ACTION_ID = 'send_test_email'
const TEST_PUSH_ACTION_ID = 'send_test_push'

// Every reason the email worker declines a send is logged behind this prefix
// (nodejs/src/cdp/services/messaging/email-validation.service.ts).
const SKIP_LOG_PREFIX = 'Skipping send:'

/**
 * The reason the worker declined to send, if it did.
 *
 * A declined send still finishes the step cleanly, so the invocation comes back `success` and the
 * reason appears only in the logs. Reading the status alone reports a test as delivered when
 * nothing was sent, and the sender waits for mail that never arrives.
 */
export function findTestSendSkipReason(result: HogflowTestResult | null): string | undefined {
    return result?.logs?.find((log) => log.message?.includes(SKIP_LOG_PREFIX))?.message
}

// The push worker logs this once per app that took the notification
// (nodejs/src/cdp/services/messaging/push-notification.service.ts).
const PUSH_ACCEPTED_LOG = /accepted by (FCM|APNs)/

/** Why a push test reached no device. A push with no registered device still finishes cleanly. */
export function findPushTestSkipReason(result: HogflowTestResult | null): string | undefined {
    if (result?.status !== 'success' || result.logs?.some((log) => PUSH_ACCEPTED_LOG.test(log.message ?? ''))) {
        return undefined
    }
    const warnings = result.logs
        ?.filter((log) => String(log.level).toLowerCase().startsWith('warn'))
        .map((log) => log.message)
    return warnings?.length
        ? warnings.join(' ')
        : 'No device took the notification. Check that this person has push turned on in your app.'
}

// Per-app delivery errors from the same worker. A missing token on one app is not one of them.
const PUSH_APP_FAILURE_LOG = /(FCM|APNs): /

export function findPushTestPartialFailure(result: HogflowTestResult | null): string | undefined {
    if (result?.status !== 'success' || !result.logs?.some((log) => PUSH_ACCEPTED_LOG.test(log.message ?? ''))) {
        return undefined
    }
    const failures = result.logs
        .filter((log) => String(log.level).toLowerCase() === 'error' || PUSH_APP_FAILURE_LOG.test(log.message ?? ''))
        .map((log) => log.message)
    return failures.length ? failures.join(' ') : undefined
}

/** Liquid prints a raw block as typed, so braces in a distinct ID never run as a template. */
export function literalDistinctIdInput(distinctId: string): { value: string; templating: 'liquid' } {
    return { value: `{% raw %}${distinctId}{% endraw %}`, templating: 'liquid' }
}

