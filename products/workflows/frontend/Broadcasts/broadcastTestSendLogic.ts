/**
 * Sends one real email to an address the user names, so they can read the broadcast in an inbox
 * before it reaches the audience. The send runs the same email step the broadcast will, through a
 * throwaway flow that exists only for this invocation.
 */
export const broadcastTestSendLogic = kea<broadcastTestSendLogicType>([
    path(['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastTestSendLogic']),
    props({} as BroadcastWizardLogicProps),
    key((props) => props.id),

    connect((props: BroadcastWizardLogicProps) => ({
        values: [
            broadcastWizardLogic(props),
            ['email', 'name'],
            broadcastPreviewLogic(props),
            ['previewPerson'],
            teamLogic,
            ['currentTeamId'],
            userLogic,
            ['user'],
        ],
    })),

    actions({
        setModalOpen: (open: boolean) => ({ open }),
        setRecipientEmail: (email: string) => ({ email }),
        clearTestSendResult: true,
    }),

    reducers({
        isModalOpen: [false, { setModalOpen: (_, { open }) => open }],
        recipientEmail: ['', { setRecipientEmail: (_, { email }) => email }],
    }),

    loaders(({ values }) => ({
        testSendResult: [
            null as HogflowTestResult | null,
            {
                clearTestSendResult: () => null,
                sendTestEmail: async (): Promise<HogflowTestResult> => {
                    const { email, name, previewPerson, recipientEmail, currentTeamId } = values

                    const emailAction: HogFlowAction = {
                        id: TEST_EMAIL_ACTION_ID,
                        type: 'function_email',
                        name: 'Send test email',
                        description: '',
                        created_at: 0,
                        updated_at: 0,
                        config: {
                            template_id: 'template-email',
                            inputs: {
                                email: {
                                    value: {
                                        ...email,
                                        // One visible recipient on a test, whatever the broadcast carries.
                                        cc: '',
                                        bcc: '',
                                        to: { email: recipientEmail, name: '' },
                                    },
                                    templating: 'liquid',
                                },
                            },
                        },
                    }

                    const edges: HogFlowEdge[] = [
                        { from: TRIGGER_NODE_ID, to: TEST_EMAIL_ACTION_ID, type: 'continue' },
                        { from: TEST_EMAIL_ACTION_ID, to: EXIT_NODE_ID, type: 'continue' },
                    ]

                    const configuration: HogFlow = {
                        ...NEW_WORKFLOW,
                        team_id: currentTeamId ?? NEW_WORKFLOW.team_id,
                        name: name || 'Test broadcast',
                        actions: [NEW_WORKFLOW.actions[0], emailAction, NEW_WORKFLOW.actions[1]],
                        edges,
                    }

                    const globals = createExampleEvent(
                        currentTeamId ?? undefined,
                        configuration.name,
                        '$pageview',
                        recipientEmail
                    )
                    if (previewPerson) {
                        // Render against the person the preview is showing, so the test email that
                        // lands is the one that person would have received.
                        globals.person = {
                            id: previewPerson.id,
                            properties: previewPerson.properties,
                            name: previewPerson.displayName,
                            url: globals.person?.url ?? '',
                        }
                    }

                    return await api.hogFlows.createTestInvocation('new', {
                        configuration,
                        globals,
                        // A test send is a real send. Mocking it would defeat the point.
                        mock_async_functions: false,
                        current_action_id: TEST_EMAIL_ACTION_ID,
                    })
                },
            },
        ],
    })),

    selectors({
        sendDisabledReason: [
            (s) => [s.email, s.recipientEmail],
            (email: BroadcastEmailValue, recipientEmail: string): string | undefined => {
                if (!email.from?.integrationId) {
                    return 'Choose an email sender first'
                }
                if (!email.subject) {
                    return 'Add a subject first'
                }
                if (!email.html && !email.text) {
                    return 'Add email content first'
                }
                if (!recipientEmail || !isEmail(recipientEmail)) {
                    return 'Enter a valid email address'
                }
                return undefined
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        setModalOpen: ({ open }) => {
            // A stale result from a previous attempt must not greet the next one.
            actions.clearTestSendResult()
            if (open && !values.recipientEmail && values.user?.email) {
                actions.setRecipientEmail(values.user.email)
            }
        },
        sendTestEmailSuccess: ({ testSendResult }) => {
            if (testSendResult?.status === 'success') {
                lemonToast.success(`Test email sent to ${values.recipientEmail}`)
                actions.setModalOpen(false)
            } else if (testSendResult?.status === 'skipped') {
                lemonToast.warning('The email step was skipped, so nothing was sent')
            } else {
                lemonToast.error('Could not send the test email')
            }
        },
        sendTestEmailFailure: () => {
            lemonToast.error('Could not send the test email')
        },
    })),
])
