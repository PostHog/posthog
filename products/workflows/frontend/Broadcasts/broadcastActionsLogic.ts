import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { lemonToast } from '@posthog/lemon-ui'

import { projectLogic } from 'scenes/projectLogic'

import {
    hogFlowsCreate,
    hogFlowsDestroy,
    hogFlowsPartialUpdate,
    hogFlowsRetrieve,
} from 'products/workflows/frontend/generated/api'

// Declared structurally rather than as a Pick: the list row types `name` as required and the full
// record types it as optional, so only a loose shape accepts both call sites.
export interface BroadcastRef {
    id: string
    name?: string | null
    status?: string | null
}

export type BroadcastAction = 'archive' | 'restore' | 'duplicate' | 'delete'

/** Which row is mid-request, so the button that started it can show it and the rest can wait. */
export interface BroadcastPendingAction {
    id: string
    action: BroadcastAction
}

export interface broadcastActionsLogicValues {
    currentProjectId: number | null // projectLogic
    pendingAction: BroadcastPendingAction | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface broadcastActionsLogicActions {
    archiveBroadcast: (broadcast: BroadcastRef) => {
        broadcast: BroadcastRef
    }
    broadcastActionCompleted: (
        action: BroadcastAction,
        broadcast: BroadcastRef
    ) => {
        action: BroadcastAction
        broadcast: BroadcastRef
    }
    deleteBroadcast: (broadcast: BroadcastRef) => {
        broadcast: BroadcastRef
    }
    duplicateBroadcast: (broadcast: BroadcastRef) => {
        broadcast: BroadcastRef
    }
    restoreBroadcast: (broadcast: BroadcastRef) => {
        broadcast: BroadcastRef
    }
    setPendingAction: (pending: BroadcastPendingAction | null) => {
        pending: BroadcastPendingAction | null
    }
}

export type broadcastActionsLogicType = MakeLogicType<broadcastActionsLogicValues, broadcastActionsLogicActions>

/**
 * `loading`/`disabledReason` for one menu entry, so a second click cannot fire the same request twice
 * and the other entries wait rather than racing it. Only one mutation runs at a time.
 */
export function broadcastActionButtonProps(
    pendingAction: BroadcastPendingAction | null,
    id: string,
    action: BroadcastAction
): { loading: boolean; disabledReason?: string } {
    const isThisOne = pendingAction?.id === id && pendingAction.action === action
    return {
        loading: isThisOne,
        disabledReason: pendingAction && !isThisOne ? 'Another broadcast action is in progress' : undefined,
    }
}

/**
 * The row and detail menus both mutate a broadcast, and both need to know when one finishes: the list
 * reloads, the detail page refreshes or navigates away. Keeping the mutations here rather than in
 * `broadcastsLogic` means opening one broadcast does not also fetch the whole list behind it.
 */
export const broadcastActionsLogic = kea<broadcastActionsLogicType>([
    path(['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastActionsLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        archiveBroadcast: (broadcast: BroadcastRef) => ({ broadcast }),
        restoreBroadcast: (broadcast: BroadcastRef) => ({ broadcast }),
        duplicateBroadcast: (broadcast: BroadcastRef) => ({ broadcast }),
        deleteBroadcast: (broadcast: BroadcastRef) => ({ broadcast }),
        broadcastActionCompleted: (action: BroadcastAction, broadcast: BroadcastRef) => ({ action, broadcast }),
        setPendingAction: (pending: BroadcastPendingAction | null) => ({ pending }),
    }),
    reducers({
        pendingAction: [
            null as BroadcastPendingAction | null,
            {
                setPendingAction: (_, { pending }) => pending,
            },
        ],
    }),
    listeners(({ actions, values }) => {
        // One shape for all four: hold the row while the request is in flight so the menu cannot fire
        // it twice, announce the change on success, and always release it — success or failure.
        const run = async (
            action: BroadcastAction,
            broadcast: BroadcastRef,
            request: (projectId: string) => Promise<void>,
            successMessage: string
        ): Promise<void> => {
            if (!values.currentProjectId || values.pendingAction) {
                return
            }
            actions.setPendingAction({ id: broadcast.id, action })
            try {
                await request(String(values.currentProjectId))
                lemonToast.success(successMessage)
                actions.broadcastActionCompleted(action, broadcast)
            } catch (error: any) {
                lemonToast.error(
                    `Couldn't ${action} the broadcast: ${error?.detail || error?.message || 'unknown error'}`
                )
            } finally {
                actions.setPendingAction(null)
            }
        }

        return {
            archiveBroadcast: async ({ broadcast }) => {
                await run(
                    'archive',
                    broadcast,
                    async (projectId) => {
                        await hogFlowsPartialUpdate(projectId, broadcast.id, { status: 'archived' })
                    },
                    'Broadcast archived'
                )
            },
            restoreBroadcast: async ({ broadcast }) => {
                await run(
                    'restore',
                    broadcast,
                    async (projectId) => {
                        await hogFlowsPartialUpdate(projectId, broadcast.id, { status: 'draft' })
                    },
                    'Broadcast restored as a draft'
                )
            },
            duplicateBroadcast: async ({ broadcast }) => {
                await run(
                    'duplicate',
                    broadcast,
                    async (projectId) => {
                        // Copy the full definition rather than the list row: the list serializer omits
                        // actions and edges, and a duplicate without them would save as an empty broadcast.
                        const full = await hogFlowsRetrieve(projectId, broadcast.id)
                        await hogFlowsCreate(projectId, {
                            ...full,
                            id: undefined,
                            name: `${full.name ?? 'Broadcast'} (copy)`,
                            status: 'draft',
                        } as any)
                    },
                    'Broadcast duplicated as a draft'
                )
            },
            deleteBroadcast: async ({ broadcast }) => {
                await run(
                    'delete',
                    broadcast,
                    async (projectId) => {
                        await hogFlowsDestroy(projectId, broadcast.id)
                    },
                    'Broadcast deleted'
                )
            },
        }
    }),
])
