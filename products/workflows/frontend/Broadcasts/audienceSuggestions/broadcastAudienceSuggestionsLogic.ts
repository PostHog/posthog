export const broadcastAudienceSuggestionsLogic = kea<broadcastAudienceSuggestionsLogicType>([
    path([
        'products',
        'workflows',
        'frontend',
        'Broadcasts',
        'audienceSuggestions',
        'broadcastAudienceSuggestionsLogic',
    ]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        giveUpPolling: true,
        pickSuggestion: (suggestion: AudienceSuggestionApi) => ({ suggestion }),
        setCreatingId: (id: string | null) => ({ id }),
    }),
    reducers({
        creatingId: [
            null as string | null,
            {
                setCreatingId: (_, { id }) => id,
            },
        ],
        pollingTimedOut: [
            false,
            {
                giveUpPolling: () => true,
            },
        ],
    }),
    loaders(({ values }) => ({
        result: [
            null as AudienceSuggestionsResponseApi | null,
            {
                // Returns the cached cards, or starts a background run and answers with status generating.
                loadResult: async (): Promise<AudienceSuggestionsResponseApi | null> => {
                    try {
                        return await broadcastAudienceSuggestionsGenerate(
                            String(values.currentProjectId),
                            {},
                            { signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS) }
                        )
                    } catch {
                        // Suggestions are optional, so a failed call shows nothing rather than an error.
                        return null
                    }
                },
                pollResult: async (): Promise<AudienceSuggestionsResponseApi | null> => {
                    try {
                        return await broadcastAudienceSuggestionsCurrent(String(values.currentProjectId), {
                            signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
                        })
                    } catch {
                        return values.result
                    }
                },
            },
        ],
    })),
    selectors({
        suggestions: [
            (s) => [s.result],
            (result: AudienceSuggestionsResponseApi | null): AudienceSuggestionApi[] =>
                result?.status === 'ready' ? result.suggestions : [],
        ],
        generating: [
            (s) => [s.result, s.resultLoading, s.pollingTimedOut],
            (result: AudienceSuggestionsResponseApi | null, loading: boolean, timedOut: boolean): boolean =>
                !timedOut && (loading || result?.status === 'generating'),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const handleResult = (result: AudienceSuggestionsResponseApi | null): void => {
            cache.disposables.dispose('poll')
            if (result?.status === 'generating') {
                if (Date.now() > cache.pollDeadline) {
                    actions.giveUpPolling()
                    return
                }
                cache.disposables.add(() => {
                    const timer = window.setTimeout(() => actions.pollResult(), POLL_INTERVAL_MS)
                    return () => window.clearTimeout(timer)
                }, 'poll')
                return
            }
            if (result?.status === 'ready' && result.suggestions.length > 0) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('broadcast audience suggestions shown', {
                    kinds: result.suggestions.map((suggestion) => suggestion.kind),
                    reachable_counts: result.suggestions.map((suggestion) => suggestion.reachable_count),
                })
            }
        }
        return {
            loadResultSuccess: ({ result }) => {
                cache.pollDeadline = Date.now() + POLL_DEADLINE_MS
                handleResult(result)
            },
            pollResultSuccess: ({ result }) => handleResult(result),
            pickSuggestion: async ({ suggestion }, breakpoint) => {
                if (values.creatingId) {
                    return
                }
                actions.setCreatingId(suggestion.id)
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('broadcast audience suggestion clicked', {
                    kind: suggestion.kind,
                    reachable_count: suggestion.reachable_count,
                })
                try {
                    const projectId = String(values.currentProjectId)
                    // A second click on the same idea reuses its cohort rather than adding a copy to the cohorts list.
                    const existing = (
                        await cohortsList(projectId, { search: suggestion.name, limit: 20 })
                    ).results.find(
                        (item) =>
                            !item.deleted &&
                            item.name === suggestion.name &&
                            item.description === suggestion.description
                    )
                    breakpoint()
                    const cohort =
                        existing ??
                        (await cohortsCreate(projectId, {
                            name: suggestion.name,
                            description: suggestion.description,
                            filters: suggestion.cohort_filters,
                            is_static: false,
                        } as Parameters<typeof cohortsCreate>[1]))
                    breakpoint()
                    router.actions.push(
                        urlForNewBroadcastWithAudience({
                            properties: [
                                {
                                    key: 'id',
                                    type: PropertyFilterType.Cohort,
                                    operator: PropertyOperator.In,
                                    value: cohort.id,
                                    cohort_name: cohort.name ?? suggestion.name,
                                },
                            ],
                            name: suggestion.name,
                            source: AUDIENCE_SUGGESTION_SOURCE,
                            draftSource: { source: 'cohort', source_id: String(cohort.id) },
                        })
                    )
                } catch (error: any) {
                    if (isBreakpoint(error)) {
                        throw error
                    }
                    lemonToast.error(error?.detail || CREATE_FAILED_MESSAGE)
                } finally {
                    if (!cache.disposables.isDisposed) {
                        actions.setCreatingId(null)
                    }
                }
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadResult()
    }),
])
