import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import {
    AI_COMPOSER_MODE_VALUE,
    EDITOR_MODE_PARAM,
    EDITOR_MODE_VALUE,
    aiComposerAvailable,
    isAiFirstVariant,
} from 'scenes/max/aiFirstCreate/aiFirstMode'
import { sceneAgentPanelLogic } from 'scenes/max/sceneAgentPanelLogic'
import { urls } from 'scenes/urls'

function isNewBroadcastRoute(pathname: string): boolean {
    return removeProjectIdIfPresent(pathname) === urls.broadcastNew()
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newBroadcastAgentLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    location: {
        pathname: string
        search: string
        hash: string
    } // router
    searchParams: Record<string, any> // router
    sceneIntegrationEnabled: boolean // sceneAgentPanelLogic
    aiComposerAvailable: boolean
    aiFirstNewEnabled: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newBroadcastAgentLogicActions {
    openWizardFromAiComposer: () => {
        value: true
    }
    startNewBroadcast: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newBroadcastAgentLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        aiFirstNewEnabled: (featureFlags: FeatureFlagsSet, sceneIntegrationEnabled: boolean) => boolean
        aiComposerAvailable: (
            featureFlags: FeatureFlagsSet,
            sceneIntegrationEnabled: boolean,
            searchParams: Record<string, any>,
            location: {
                hash: string
                pathname: string
                search: string
            }
        ) => boolean
    }
}

export type newBroadcastAgentLogicType = MakeLogicType<
    newBroadcastAgentLogicValues,
    newBroadcastAgentLogicActions,
    Record<string, any>,
    newBroadcastAgentLogicMeta
>

/** Entry and mode for the AI-first "New broadcast" page. */
export const newBroadcastAgentLogic = kea<newBroadcastAgentLogicType>([
    path(['products', 'workflows', 'frontend', 'Broadcasts', 'newBroadcastAgentLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            sceneAgentPanelLogic,
            ['sceneIntegrationEnabled'],
            router,
            ['searchParams', 'location'],
        ],
    })),
    actions({
        startNewBroadcast: true,
        openWizardFromAiComposer: true,
    }),
    selectors({
        // Same gate as the scene integration. Only the `test` variant, or a plain boolean rollout, qualifies.
        aiFirstNewEnabled: [
            (s) => [s.featureFlags, s.sceneIntegrationEnabled],
            (featureFlags: FeatureFlagsSet, sceneIntegrationEnabled: boolean): boolean =>
                sceneIntegrationEnabled && isAiFirstVariant(FEATURE_FLAGS.BROADCASTS_AI_FIRST_NEW, featureFlags),
        ],
        aiComposerAvailable: [
            (s) => [s.featureFlags, s.sceneIntegrationEnabled, s.searchParams, s.location],
            (
                featureFlags: FeatureFlagsSet,
                sceneIntegrationEnabled: boolean,
                searchParams: Record<string, any>,
                location: { pathname: string }
            ): boolean =>
                aiComposerAvailable(
                    FEATURE_FLAGS.BROADCASTS_AI_FIRST_NEW,
                    featureFlags,
                    sceneIntegrationEnabled,
                    searchParams,
                    isNewBroadcastRoute(location.pathname)
                ),
        ],
    }),
    listeners(({ values }) => ({
        startNewBroadcast: () => {
            // Exposure is recorded at the click, and only when the composer could answer it.
            if (values.sceneIntegrationEnabled) {
                posthog.getFeatureFlag(FEATURE_FLAGS.BROADCASTS_AI_FIRST_NEW)
            }
            router.actions.push(
                urls.broadcastNew(),
                values.aiFirstNewEnabled ? { [EDITOR_MODE_PARAM]: AI_COMPOSER_MODE_VALUE } : {}
            )
        },
        // The editor URL keeps the composer from rendering again, so the wizard mounts in its place.
        openWizardFromAiComposer: () => {
            router.actions.push(urls.broadcastNew(), { [EDITOR_MODE_PARAM]: EDITOR_MODE_VALUE })
        },
    })),
])
