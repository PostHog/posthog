import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { subscriptions } from 'kea-subscriptions'

import { projectLogic } from 'scenes/projectLogic'

import { AnyPropertyFilter, PropertyFilterType } from '~/types'

import { cohortsRetrieve } from 'products/cohorts/frontend/generated/api'

import { BroadcastWizardLogicProps, broadcastWizardLogic } from '../broadcastWizardLogic'

export interface AudienceCohort {
    id: number
    name: string
    isStatic: boolean
    isCalculating: boolean
    failed: boolean
    count: number | null
    // Set for a cohort made from a list: how many people were on it and how many of them PostHog didn't find.
    importTotal: number | null
    importUnmatched: number | null
}

const POLL_MS = 3000

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface broadcastAudienceCohortsLogicValues {
    audienceProperties: AnyPropertyFilter[] // broadcastWizardLogic
    currentProjectId: number | null // projectLogic
    audienceCohorts: Record<number, AudienceCohort | null>
    cohortIds: number[]
    nonCohortAudience: AnyPropertyFilter[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface broadcastAudienceCohortsLogicActions {
    loadBlastRadius: () => any // broadcastWizardLogic
    loadAudienceCohorts: () => {
        value: true
    }
    setAudienceCohorts: (cohorts: Record<number, AudienceCohort | null>) => {
        cohorts: Record<number, AudienceCohort | null>
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface broadcastAudienceCohortsLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        nonCohortAudience: (audienceProperties: AnyPropertyFilter[]) => AnyPropertyFilter[]
        cohortIds: (audienceProperties: AnyPropertyFilter[]) => number[]
    }
}

export type broadcastAudienceCohortsLogicType = MakeLogicType<
    broadcastAudienceCohortsLogicValues,
    broadcastAudienceCohortsLogicActions,
    BroadcastWizardLogicProps,
    broadcastAudienceCohortsLogicMeta
>

export const broadcastAudienceCohortsLogic = kea<broadcastAudienceCohortsLogicType>([
    path(['products', 'workflows', 'frontend', 'Broadcasts', 'audience', 'broadcastAudienceCohortsLogic']),
    props({} as BroadcastWizardLogicProps),
    key((props) => props.id),
    connect((props: BroadcastWizardLogicProps) => ({
        values: [broadcastWizardLogic(props), ['audienceProperties'], projectLogic, ['currentProjectId']],
        actions: [broadcastWizardLogic(props), ['loadBlastRadius']],
    })),
    actions({
        loadAudienceCohorts: true,
        setAudienceCohorts: (cohorts: Record<number, AudienceCohort | null>) => ({ cohorts }),
    }),
    reducers({
        audienceCohorts: [
            {} as Record<number, AudienceCohort | null>,
            {
                setAudienceCohorts: (_, { cohorts }) => cohorts,
            },
        ],
    }),
    selectors({
        // The audience's other conditions. The cohorts in it are shown as cards with a link instead.
        nonCohortAudience: [
            (s) => [s.audienceProperties],
            (audienceProperties: AnyPropertyFilter[]): AnyPropertyFilter[] =>
                audienceProperties.filter((filter) => filter.type !== PropertyFilterType.Cohort),
        ],
        cohortIds: [
            (s) => [s.audienceProperties],
            (audienceProperties: AnyPropertyFilter[]): number[] => [
                ...new Set(
                    audienceProperties
                        .filter((filter) => filter.type === PropertyFilterType.Cohort)
                        .map((filter) => Number(filter.value))
                        .filter((id) => Number.isFinite(id))
                ),
            ],
        ],
    }),
    listeners(({ actions, values }) => ({
        loadAudienceCohorts: async (_, breakpoint) => {
            await breakpoint(100)
            const ids = values.cohortIds
            if (!values.currentProjectId || ids.length === 0) {
                actions.setAudienceCohorts({})
                return
            }
            const projectId = String(values.currentProjectId)
            const loaded = await Promise.all(
                ids.map(async (id): Promise<[number, AudienceCohort | null]> => {
                    try {
                        const cohort = await cohortsRetrieve(projectId, id)
                        return [
                            id,
                            {
                                id,
                                name: cohort.name ?? `Cohort ${id}`,
                                isStatic: !!cohort.is_static,
                                isCalculating: !!cohort.is_calculating,
                                failed: (cohort.errors_calculating ?? 0) > 0 && !cohort.is_calculating,
                                count: cohort.count ?? null,
                                importTotal: cohort.last_import_total_count ?? null,
                                importUnmatched: cohort.last_import_unmatched_count ?? null,
                            },
                        ]
                    } catch (error: any) {
                        // A failed poll keeps the last card, so a cohort that is still matching keeps polling.
                        // A deleted cohort has nothing left to show.
                        return [id, error?.status === 404 ? null : (values.audienceCohorts[id] ?? null)]
                    }
                })
            )
            breakpoint()
            const previous = values.audienceCohorts
            const cohorts = Object.fromEntries(loaded)
            actions.setAudienceCohorts(cohorts)
            // The audience size counts a cohort's members, so it is stale until matching finishes.
            if (ids.some((id) => previous[id]?.isCalculating && cohorts[id] && !cohorts[id]!.isCalculating)) {
                actions.loadBlastRadius()
            }
            if (Object.values(cohorts).some((cohort) => cohort?.isCalculating)) {
                await breakpoint(POLL_MS)
                actions.loadAudienceCohorts()
            }
        },
    })),
    subscriptions(({ actions }) => ({
        cohortIds: (next: number[], previous?: number[]) => {
            if (previous !== undefined && next.join() !== previous.join()) {
                actions.loadAudienceCohorts()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadAudienceCohorts()
    }),
])
