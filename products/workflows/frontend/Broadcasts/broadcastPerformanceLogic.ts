export type broadcastPerformanceLogicType = MakeLogicType<
    broadcastPerformanceLogicValues,
    broadcastPerformanceLogicActions,
    BroadcastPerformanceLogicProps,
    broadcastPerformanceLogicMeta
>

export const broadcastPerformanceLogic = kea<broadcastPerformanceLogicType>([
    path((runId) => ['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastPerformanceLogic', runId]),
    props({} as BroadcastPerformanceLogicProps),
    key((props) => props.runId),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
    })),
    loaders(({ props, values }) => {
        const window = (): { dateFrom: string; dateTo: string } => ({
            dateFrom: dayjs(props.runStartedAt).subtract(1, 'hour').toISOString(),
            dateTo: dayjs().add(1, 'hour').toISOString(),
        })
        return {
            totals: [
                null as Record<string, number> | null,
                {
                    loadTotals: async () => {
                        const timezone = values.currentTeam?.timezone ?? 'UTC'
                        const [response, failedResponse] = await Promise.all([
                            loadAppMetricsTotals(
                                {
                                    appSource: 'hog_flow',
                                    appSourceId: props.runId,
                                    metricName: TOTALS_METRICS,
                                    breakdownBy: ['metric_name'],
                                    ...window(),
                                },
                                timezone
                            ),
                            loadAppMetricsTotals(
                                {
                                    appSource: 'hog_flow',
                                    appSourceId: props.runId,
                                    metricName: ['failed'],
                                    breakdownBy: ['instance_id'],
                                    ...window(),
                                },
                                timezone
                            ),
                        ])
                        return {
                            ...Object.fromEntries(
                                Object.values(response).map(({ total, breakdowns }) => [breakdowns[0], total])
                            ),
                            [STEP_FAILED_KEY]: sumStepFailures(failedResponse),
                        }
                    },
                },
            ],
            links: [
                [] as EmailLinkRow[],
                {
                    loadLinks: async () => {
                        const response = await loadAppMetricsTotals(
                            {
                                appSource: 'hog_flow',
                                appSourceId: props.runId,
                                metricName: ['email_link_clicked_by_link'],
                                breakdownBy: ['instance_id'],
                                limit: 100,
                                ...window(),
                            },
                            values.currentTeam?.timezone ?? 'UTC'
                        )
                        // A broadcast has one email step, so its links are every link in the run.
                        return Object.values(parseEmailLinkTotals(response))
                            .flat()
                            .sort((a, b) => b.clicks - a.clicks)
                    },
                },
            ],
        }
    }),
    reducers({
        totalsFailed: [
            false,
            {
                loadTotals: () => false,
                loadTotalsSuccess: () => false,
                loadTotalsFailure: () => true,
            },
        ],
    }),
    selectors({
        stats: [
            (s) => [s.totals],
            (totals: Record<string, number> | null): BroadcastPerformanceStats | null => buildPerformanceStats(totals),
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadTotals()
        actions.loadLinks()
    }),
])
