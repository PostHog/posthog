export const broadcastPerformanceLogic = kea<broadcastPerformanceLogicType>([
    path((runId) => ['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastPerformanceLogic', runId]),
    props({} as BroadcastPerformanceLogicProps),
    key((props) => props.runId),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
    })),
    loaders(({ props, values }) => {
        const window = (): { dateFrom: string; dateTo: string } => ({
            dateFrom: dayjs(props.runStartedAt).subtract(1, 'hour').toISOString(),
            dateTo: dayjs().add(1, 'hour').toISOString(),
        })
        return {
            totals: [
                null as Record<string, number> | null,
                {
                    loadTotals: async () => {
                        const response = await loadAppMetricsTotals(
                            {
                                appSource: 'hog_flow',
                                appSourceId: props.runId,
                                metricName: TOTALS_METRICS,
                                breakdownBy: ['metric_name', 'instance_id'],
                                ...window(),
                            },
                            values.currentTeam?.timezone ?? 'UTC'
                        )
                        const totals: Record<string, number> = {}
                        for (const { total, breakdowns } of Object.values(response)) {
                            const [metricName, instanceId] = breakdowns
                            // A step that aborts the run also records a run-level `failed`, which would count each
                            // person twice, so only step-level failures count people who weren't sent anything.
                            if (metricName === 'failed' && !instanceId) {
                                continue
                            }
                            totals[metricName] = (totals[metricName] ?? 0) + total
                        }
                        return totals
                    },
                },
            ],
            latestErrorLog: [
                null as string | null,
                {
                    loadLatestErrorLog: async () => {
                        const response = await api.queryHogQL<[string]>(
                            hogql`
                                SELECT message
                                FROM log_entries
                                WHERE log_source = 'hog_flow'
                                    AND log_source_id = ${props.runId}
                                    AND lower(level) = 'error'
                                    AND timestamp > {filters.dateRange.from}
                                ORDER BY startsWith(message, '[Action:') DESC, timestamp DESC
                                LIMIT 1`,
                            {
                                scene: Scene.Broadcast,
                                productKey: ProductKey.WORKFLOWS,
                                name: 'broadcast_run_latest_error',
                            },
                            { refresh: 'force_blocking', filtersOverride: { date_from: window().dateFrom } }
                        )
                        return response.results?.[0]?.[0] ?? null
                    },
                },
            ],
            links: [
                [] as EmailLinkRow[],
                {
                    loadLinks: async () => {
                        const response = await loadAppMetricsTotals(
                            {
                                appSource: 'hog_flow',
                                appSourceId: props.runId,
                                metricName: ['email_link_clicked_by_link'],
                                breakdownBy: ['instance_id'],
                                limit: 100,
                                ...window(),
                            },
                            values.currentTeam?.timezone ?? 'UTC'
                        )
                        // A broadcast has one email step, so its links are every link in the run.
                        return Object.values(parseEmailLinkTotals(response))
                            .flat()
                            .sort((a, b) => b.clicks - a.clicks)
                    },
                },
            ],
        }
    }),
    reducers({
        totalsFailed: [
            false,
            {
                loadTotals: () => false,
                loadTotalsSuccess: () => false,
                loadTotalsFailure: () => true,
            },
        ],
    }),
    selectors({
        stats: [
            (s) => [
                s.totals,
                (_, props: BroadcastPerformanceLogicProps) => props.channel,
                (_, props: BroadcastPerformanceLogicProps) => props.runStartedAt,
            ],
            (
                totals: Record<string, number> | null,
                channel: BroadcastChannel | undefined,
                runStartedAt: string
            ): BroadcastPerformanceStats | null => {
                if (!totals) {
                    return null
                }
                if (channel === 'push') {
                    const pushSent = totals.push_sent ?? 0
                    // Push has no delivery receipts or link tracking, so every send counts as tracked.
                    return {
                        sent: pushSent,
                        delivered: 0,
                        opened: totals.push_opened ?? 0,
                        clicked: 0,
                        bounced: 0,
                        markedAsSpam: 0,
                        failed: totals.push_failed ?? 0,
                        trackedSends: pushSent,
                        engagementCountsPeople: true,
                        converted: totals.conversion ?? 0,
                        skipped: totals.push_skipped ?? 0,
                        unsubscribed: 0,
                    }
                }
                const sent = totals.email_sent ?? 0
                return {
                    sent,
                    delivered: totals.email_delivered ?? 0,
                    opened: emailEngagement(totals, 'opened', runStartedAt),
                    clicked: emailEngagement(totals, 'clicked', runStartedAt),
                    engagementCountsPeople: countsEngagedPeople(totals, runStartedAt),
                    bounced: totals.email_bounced ?? 0,
                    // Spam complaints are stored under email_blocked.
                    markedAsSpam: totals.email_blocked ?? 0,
                    failed: totals.email_failed ?? 0,
                    unsubscribed: totals.email_unsubscribed ?? 0,
                    trackedSends: Math.max(sent - (totals.email_untracked ?? 0), 0),
                    converted: totals.conversion ?? 0,
                    skipped: 0,
                }
            },
        ],
        sendCounts: [
            (s) => [s.totals, (_, props: BroadcastPerformanceLogicProps) => props.channel],
            (
                totals: Record<string, number> | null,
                channel: BroadcastChannel | undefined
            ): BroadcastSendCounts | null => getSendCounts(totals, channel),
        ],
        sendError: [
            (s) => [s.latestErrorLog, (_, props: BroadcastPerformanceLogicProps) => props.channel],
            (latestErrorLog: string | null, channel: BroadcastChannel | undefined): BroadcastSendError | null =>
                latestErrorLog ? describeSendError(latestErrorLog, channel) : null,
        ],
        audience: [
            (s) => [s.totals, (_, props: BroadcastPerformanceLogicProps) => props.runStartedAt],
            (totals: Record<string, number> | null, runStartedAt: string): RunAudience | null =>
                getRunAudience(totals, runStartedAt),
        ],
        // Null when the team doesn't hold capped emails.
        capHoldHours: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): number | null => {
                const config = currentTeam && 'workflows_config' in currentTeam ? currentTeam.workflows_config : null
                return config?.marketing_frequency_cap_hold_hours || null
            },
        ],
        // Every email went out with open and click tracking off, so no open or click can ever be counted.
        trackingOff: [
            (s) => [s.stats],
            (stats: BroadcastPerformanceStats | null): boolean => !!stats && stats.sent > 0 && stats.trackedSends === 0,
        ],
    }),
    listeners(({ actions }) => ({
        loadTotalsSuccess: ({ totals }) => {
            if ((totals.failed ?? 0) > 0) {
                actions.loadLatestErrorLog()
            }
        },
    })),
    afterMount(({ actions, props }) => {
        actions.loadTotals()
        if (props.channel !== 'push') {
            actions.loadLinks()
        }
    }),
])
