export interface BroadcastPerformanceLogicProps {
    /** The batch run the numbers belong to. A batch send's email metrics are recorded against the run, not the flow. */
    runId: string
    runStartedAt: string
    channel?: BroadcastChannel
}

export interface BroadcastPerformanceStats {
    sent: number
    delivered: number
    opened: number
    clicked: number
    bounced: number
    markedAsSpam: number
    failed: number
    unsubscribed: number
    /** Sends with open and click tracking, the denominator for engagement rates. */
    trackedSends: number
    /** False for sends from before people were counted, where opened and clicked count every event. */
    engagementCountsPeople: boolean
    /** Recipients who met the broadcast's goal. */
    converted: number
    /** Push only: people with no device registered for the app. */
    skipped: number
}

// Runs that started before this date counted events. A late open on one adds a per-person count that covers only itself.
const ENGAGEMENT_PEOPLE_COUNTED_SINCE = dayjs('2026-11-06T00:00:00Z')

/** Whether opened and clicked count people for this run, rather than every event. */
export function countsEngagedPeople(totals: Record<string, number>, runStartedAt: string | null | undefined): boolean {
    if (!runStartedAt || dayjs(runStartedAt).isBefore(ENGAGEMENT_PEOPLE_COUNTED_SINCE)) {
        return false
    }
    // Events with no per-person count mean Redis was unavailable, so the events are the better number.
    return !!(
        totals.email_opened_by_person ||
        totals.email_clicked_by_person ||
        (!totals.email_opened && !totals.email_link_clicked)
    )
}

export function emailEngagement(
    totals: Record<string, number>,
    kind: 'opened' | 'clicked',
    runStartedAt: string | null | undefined
): number {
    if (countsEngagedPeople(totals, runStartedAt)) {
        return (kind === 'opened' ? totals.email_opened_by_person : totals.email_clicked_by_person) ?? 0
    }
    return (kind === 'opened' ? totals.email_opened : totals.email_link_clicked) ?? 0
}

const TOTALS_METRICS = [
    'email_sent',
    'email_delivered',
    'email_opened',
    'email_link_clicked',
    'email_opened_by_person',
    'email_clicked_by_person',
    'email_bounced',
    'email_blocked',
    'email_failed',
    'email_untracked',
    'push_sent',
    'push_skipped',
    'push_failed',
    'push_opened',
    'email_unsubscribed',
    'conversion',
    // Recorded when a step throws, so a send that never reached the provider has no email_failed or push_failed.
    'failed',
    ...RUN_AUDIENCE_METRICS,
]

const SEND_ACTIVITY_METRICS: Record<BroadcastChannel, string[]> = {
    email: ['email_sent', 'email_delivered', 'email_opened', 'email_link_clicked'],
    push: ['push_sent', 'push_opened'],
}

/** Hourly buckets read well for a few days after a send, then the tail of late opens needs daily ones. */
const HOURLY_WINDOW_DAYS = 3

export function sendActivityParams(
    runId: string,
    runStartedAt: string,
    now: Dayjs = dayjs(),
    channel: BroadcastChannel = 'email'
): Partial<AppMetricsCommonParams> {
    const started = dayjs(runStartedAt)
    const interval = now.diff(started, 'day', true) <= HOURLY_WINDOW_DAYS ? 'hour' : 'day'
    return {
        // A batch send's email metrics are recorded against the run, not the flow.
        appSource: 'hog_flow',
        appSourceId: runId,
        breakdownBy: 'metric_name',
        metricName: SEND_ACTIVITY_METRICS[channel],
        interval,
        dateFrom: started.toISOString(),
    }
}

