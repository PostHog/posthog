export type broadcastPerformanceLogicType = MakeLogicType<
    broadcastPerformanceLogicValues,
    broadcastPerformanceLogicActions,
    BroadcastPerformanceLogicProps,
    broadcastPerformanceLogicMeta
>

export const broadcastPerformanceLogic = kea<broadcastPerformanceLogicType>([
    path((runId) => ['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastPerformanceLogic', runId]),
    props({} as BroadcastPerformanceLogicProps),
    key((props) => props.runId),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
    })),
    loaders(({ props, values }) => {
        const window = (): { dateFrom: string; dateTo: string } => ({
            dateFrom: dayjs(props.runStartedAt).subtract(1, 'hour').toISOString(),
            dateTo: dayjs().add(1, 'hour').toISOString(),
        })
        return {
            totals: [
                null as Record<string, number> | null,
                {
                    loadTotals: async () => {
                        const response = await loadAppMetricsTotals(
                            {
                                appSource: 'hog_flow',
                                appSourceId: props.runId,
                                metricName: TOTALS_METRICS,
                                breakdownBy: ['metric_name'],
                                ...window(),
                            },
                            values.currentTeam?.timezone ?? 'UTC'
                        )
                        return Object.fromEntries(
                            Object.values(response).map(({ total, breakdowns }) => [breakdowns[0], total])
                        )
                    },
                },
            ],
            links: [
                [] as EmailLinkRow[],
                {
                    loadLinks: async () => {
                        const response = await loadAppMetricsTotals(
                            {
                                appSource: 'hog_flow',
                                appSourceId: props.runId,
                                metricName: ['email_link_clicked_by_link'],
                                breakdownBy: ['instance_id'],
                                limit: 100,
                                ...window(),
                            },
                            values.currentTeam?.timezone ?? 'UTC'
                        )
                        // A broadcast has one email step, so its links are every link in the run.
                        return Object.values(parseEmailLinkTotals(response))
                            .flat()
                            .sort((a, b) => b.clicks - a.clicks)
                    },
                },
            ],
        }
    }),
    reducers({
        totalsFailed: [
            false,
            {
                loadTotals: () => false,
                loadTotalsSuccess: () => false,
                loadTotalsFailure: () => true,
            },
        ],
    }),
    selectors({
        stats: [
            (s) => [s.totals, (_, props: BroadcastPerformanceLogicProps) => props.channel],
            (
                totals: Record<string, number> | null,
                channel: BroadcastChannel | undefined
            ): BroadcastPerformanceStats | null => {
                if (!totals) {
                    return null
                }
                if (channel === 'push') {
                    const pushSent = totals.push_sent ?? 0
                    // Push has no delivery receipts or link tracking, so every send counts as tracked.
                    return {
                        sent: pushSent,
                        delivered: 0,
                        opened: totals.push_opened ?? 0,
                        clicked: 0,
                        bounced: 0,
                        markedAsSpam: 0,
                        failed: totals.push_failed ?? 0,
                        trackedSends: pushSent,
                        converted: totals.conversion ?? 0,
                        skipped: totals.push_skipped ?? 0,
                        unsubscribed: 0,
                    }
                }
                const sent = totals.email_sent ?? 0
                return {
                    sent,
                    delivered: totals.email_delivered ?? 0,
                    opened: totals.email_opened ?? 0,
                    clicked: totals.email_link_clicked ?? 0,
                    bounced: totals.email_bounced ?? 0,
                    // Spam complaints are stored under email_blocked.
                    markedAsSpam: totals.email_blocked ?? 0,
                    failed: totals.email_failed ?? 0,
                    unsubscribed: totals.email_unsubscribed ?? 0,
                    trackedSends: Math.max(sent - (totals.email_untracked ?? 0), 0),
                    converted: totals.conversion ?? 0,
                    skipped: 0,
                }
            },
        ],
        // Every email went out with open and click tracking off, so no open or click can ever be counted.
        trackingOff: [
            (s) => [s.stats],
            (stats: BroadcastPerformanceStats | null): boolean => !!stats && stats.sent > 0 && stats.trackedSends === 0,
        ],
    }),
    afterMount(({ actions, props }) => {
        actions.loadTotals()
        if (props.channel !== 'push') {
            actions.loadLinks()
        }
    }),
])
