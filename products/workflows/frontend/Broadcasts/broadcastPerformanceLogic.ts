import { MakeLogicType, afterMount, connect, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { loadAppMetricsTotals } from 'lib/components/AppMetrics/appMetricsLogic'
import { dayjs } from 'lib/dayjs'
import { teamLogic } from 'scenes/teamLogic'

import type { TeamPublicType, TeamType } from '../../../../frontend/src/types'
import { type EmailLinkRow, parseEmailLinkTotals } from '../Workflows/workflowMetricsSummaryLogic'

export interface BroadcastPerformanceLogicProps {
    /** The batch run the numbers belong to. A batch send's email metrics are recorded against the run, not the flow. */
    runId: string
    runStartedAt: string
}

export interface BroadcastPerformanceStats {
    sent: number
    delivered: number
    opened: number
    clicked: number
    bounced: number
    markedAsSpam: number
    failed: number
    /** Sends with open and click tracking, the denominator for engagement rates. */
    trackedSends: number
}

const TOTALS_METRICS = [
    'email_sent',
    'email_delivered',
    'email_opened',
    'email_link_clicked',
    'email_bounced',
    'email_blocked',
    'email_failed',
    'email_untracked',
]

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface broadcastPerformanceLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    links: EmailLinkRow[]
    linksLoading: boolean
    stats: BroadcastPerformanceStats | null
    totals: Record<string, number> | null
    totalsFailed: boolean
    totalsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface broadcastPerformanceLogicActions {
    loadLinks: () => any
    loadLinksFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadLinksSuccess: (
        links: EmailLinkRow[],
        payload?: any
    ) => {
        links: EmailLinkRow[]
        payload?: any
    }
    loadTotals: () => any
    loadTotalsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTotalsSuccess: (
        totals: {
            [k: string]: number
        },
        payload?: any
    ) => {
        totals: {
            [k: string]: number
        }
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface broadcastPerformanceLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        stats: (totals: Record<string, number> | null) => BroadcastPerformanceStats | null
    }
}

export type broadcastPerformanceLogicType = MakeLogicType<
    broadcastPerformanceLogicValues,
    broadcastPerformanceLogicActions,
    BroadcastPerformanceLogicProps,
    broadcastPerformanceLogicMeta
>

export const broadcastPerformanceLogic = kea<broadcastPerformanceLogicType>([
    path((runId) => ['products', 'workflows', 'frontend', 'Broadcasts', 'broadcastPerformanceLogic', runId]),
    props({} as BroadcastPerformanceLogicProps),
    key((props) => props.runId),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
    })),
    loaders(({ props, values }) => {
        const window = (): { dateFrom: string; dateTo: string } => ({
            dateFrom: dayjs(props.runStartedAt).subtract(1, 'hour').toISOString(),
            dateTo: dayjs().add(1, 'hour').toISOString(),
        })
        return {
            totals: [
                null as Record<string, number> | null,
                {
                    loadTotals: async () => {
                        const response = await loadAppMetricsTotals(
                            {
                                appSource: 'hog_flow',
                                appSourceId: props.runId,
                                metricName: TOTALS_METRICS,
                                breakdownBy: ['metric_name'],
                                ...window(),
                            },
                            values.currentTeam?.timezone ?? 'UTC'
                        )
                        return Object.fromEntries(
                            Object.values(response).map(({ total, breakdowns }) => [breakdowns[0], total])
                        )
                    },
                },
            ],
            links: [
                [] as EmailLinkRow[],
                {
                    loadLinks: async () => {
                        const response = await loadAppMetricsTotals(
                            {
                                appSource: 'hog_flow',
                                appSourceId: props.runId,
                                metricName: ['email_link_clicked_by_link'],
                                breakdownBy: ['instance_id'],
                                limit: 100,
                                ...window(),
                            },
                            values.currentTeam?.timezone ?? 'UTC'
                        )
                        // A broadcast has one email step, so its links are every link in the run.
                        return Object.values(parseEmailLinkTotals(response))
                            .flat()
                            .sort((a, b) => b.clicks - a.clicks)
                    },
                },
            ],
        }
    }),
    reducers({
        totalsFailed: [
            false,
            {
                loadTotals: () => false,
                loadTotalsSuccess: () => false,
                loadTotalsFailure: () => true,
            },
        ],
    }),
    selectors({
        stats: [
            (s) => [s.totals],
            (totals: Record<string, number> | null): BroadcastPerformanceStats | null => {
                if (!totals) {
                    return null
                }
                const sent = totals.email_sent ?? 0
                return {
                    sent,
                    delivered: totals.email_delivered ?? 0,
                    opened: totals.email_opened ?? 0,
                    clicked: totals.email_link_clicked ?? 0,
                    bounced: totals.email_bounced ?? 0,
                    // Spam complaints are stored under email_blocked.
                    markedAsSpam: totals.email_blocked ?? 0,
                    failed: totals.email_failed ?? 0,
                    trackedSends: Math.max(sent - (totals.email_untracked ?? 0), 0),
                }
            },
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadTotals()
        actions.loadLinks()
    }),
])
