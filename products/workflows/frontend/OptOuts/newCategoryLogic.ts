export const newCategoryLogic = kea<newCategoryLogicType>([
    path(['products', 'workflows', 'frontend', 'OptOuts', 'newCategoryLogic']),
    props({} as CategoryLogicProps),
    key((props: CategoryLogicProps) => props.category?.id || 'new'),
    connect(() => ({
        values: [topicVocabularyLogic, ['words', 'speaksAudience']],
    })),

    actions({
        submitForm: true,
        resetForm: true,
    }),

    forms(({ actions, props, values }) => ({
        categoryForm: {
            defaults: props.category
                ? {
                      name: props.category.name,
                      key: props.category.key,
                      description: props.category.description ?? '',
                      public_description: props.category.public_description ?? '',
                      category_type: props.category.category_type ?? 'marketing',
                  }
                : NEW_CATEGORY,
            errors: ({ name, key }: CategoryForm) => {
                const keyRegex = /^[a-zA-Z0-9_-]+$/
                return {
                    name: !name.trim() ? 'Name is required' : undefined,
                    key: !key.trim()
                        ? 'Key is required'
                        : !keyRegex.test(key)
                          ? 'Only letters, numbers, hyphens (-) & underscores (_) are allowed'
                          : key.length > TOPIC_KEY_MAX_LENGTH
                            ? `Keys can be at most ${TOPIC_KEY_MAX_LENGTH} characters`
                            : undefined,
                }
            },
            submit: async (formValues: CategoryForm) => {
                const teamId = String(ApiConfig.getCurrentTeamId())
                if (props.category) {
                    await messagingCategoriesPartialUpdate(teamId, props.category.id, formValues)
                    lemonToast.success(values.words.topicForm.updated)
                    captureTopicsUsage('messaging topic updated')
                } else {
                    await messagingCategoriesCreate(teamId, formValues)
                    lemonToast.success(values.words.topicForm.created)
                    captureTopicsUsage('messaging topic created')
                }
                optOutCategoriesLogic.actions.loadCategories()
                actions.resetForm()
                props.onSuccess?.()
            },
        },
    })),

    reducers({
        keyTypedByHand: [
            false,
            {
                setCategoryFormValue: (typedByHand, { name, value }) =>
                    fieldName(name) === 'key' ? value !== '' : typedByHand,
                resetCategoryForm: () => false,
            },
        ],
    }),

    listeners(({ actions, props, values }) => ({
        resetForm: () => {
            actions.resetCategoryForm()
        },
        submitCategoryFormFailure: ({ error }) => {
            if (values.categoryFormHasErrors) {
                return
            }
            if (error instanceof ApiError && error.attr === 'key') {
                actions.setCategoryFormManualErrors({ key: values.words.topicForm.keyTaken })
            } else if (error instanceof ApiError && error.attr === 'name' && error.detail) {
                actions.setCategoryFormManualErrors({ name: error.detail })
            } else {
                lemonToast.error(values.words.topicForm.saveFailed)
            }
        },
        setCategoryFormValue: ({ name }) => {
            if (Object.keys(values.categoryFormManualErrors).length > 0) {
                actions.setCategoryFormManualErrors({})
            }
            const keyFollowsName = values.speaksAudience && !props.category && !values.keyTypedByHand
            if (fieldName(name) === 'name' && keyFollowsName) {
                actions.setCategoryFormValues({ key: topicKeyFromName(values.categoryForm.name) })
            }
        },
    })),
])
