async function parseCsvFile(file: File): Promise<string[][]> {
    return new Promise((resolve, reject) => {
        Papa.parse<string[]>(file, {
            skipEmptyLines: 'greedy',
            complete: (results) => resolve(results.data),
            error: (error: Error) => reject(error),
        })
    })
}

