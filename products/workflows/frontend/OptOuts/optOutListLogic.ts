export const optOutListLogic = kea<optOutListLogicType>([
    key((props) => props.category?.id || '$all'),
    path(['products', 'workflows', 'frontend', 'OptOuts', 'optOutListLogic']),
    props({} as OptOutListLogicProps),
    connect(() => ({
        values: [optOutSceneLogic, ['preferencesUrlLoading']],
        actions: [optOutSceneLogic, ['openPreferencesPage']],
    })),
    actions({
        loadUnsubscribeLink: true,
        setPersonsModalOpen: (open: boolean) => ({ open }),
        setManagePreferencesModalOpen: (open: boolean) => ({ open }),
        setSelectedIdentifier: (identifier: string | null) => ({ identifier }),
        setCurrentPage: (page: number) => ({ page }),
        loadNextPage: true,
        loadPreviousPage: true,
        setShowAddOptOutModal: (show: boolean) => ({ show }),
        setNewOptOutIdentifier: (identifier: string) => ({ identifier }),
        setShowImportCsvModal: (show: boolean) => ({ show }),
        setCsvFile: (file: File | null) => ({ file }),
        setCsvImportProgress: (progress: { processed: number; total: number } | null) => ({ progress }),
    }),
    reducers({
        personsModalOpen: [
            false,
            {
                setPersonsModalOpen: (_, { open }) => open,
                setSelectedIdentifier: (open, { identifier }) => {
                    if (!identifier) {
                        return false
                    }
                    return open
                },
            },
        ],
        managePreferencesModalOpen: [
            false,
            {
                setManagePreferencesModalOpen: (_, { open }) => open,
                setSelectedIdentifier: (open, { identifier }) => {
                    if (!identifier) {
                        return false
                    }
                    return open
                },
            },
        ],
        selectedIdentifier: [
            null as string | null,
            {
                setSelectedIdentifier: (_, { identifier }) => identifier,
            },
        ],
        currentPage: [
            1,
            {
                setCurrentPage: (_, { page }) => page,
                loadOptOutPersonsSuccess: () => 1, // Reset to page 1 on initial load
                loadNextPageSuccess: (state) => state + 1,
                loadPreviousPageSuccess: (state) => Math.max(1, state - 1),
            },
        ],
        showAddOptOutModal: [
            false,
            {
                setShowAddOptOutModal: (_, { show }) => show,
                addOptOutSuccess: () => false,
            },
        ],
        newOptOutIdentifier: [
            '',
            {
                setNewOptOutIdentifier: (_, { identifier }) => identifier,
                addOptOutSuccess: () => '',
                setShowAddOptOutModal: (state, { show }) => (show ? state : ''),
            },
        ],
        showImportCsvModal: [
            false,
            {
                setShowImportCsvModal: (_, { show }) => show,
            },
        ],
        csvFile: [
            null as File | null,
            {
                setCsvFile: (_, { file }) => file,
                setShowImportCsvModal: () => null,
                // Clear the picked file once an import produced a result, so the drop zone
                // is ready for the next file; keep it when the file couldn't be read at all.
                importCsvSuccess: (state, { csvImportResult }) => (csvImportResult ? null : state),
            },
        ],
        csvImportProgress: [
            null as { processed: number; total: number } | null,
            {
                setCsvImportProgress: (_, { progress }) => progress,
                importCsvSuccess: () => null,
                importCsvFailure: () => null,
                clearCsvImportResult: () => null,
            },
        ],
    }),
    loaders(({ props, values, actions }) => ({
        addOptOut: {
            __default: null as OptOutEntry | null,
            addOptOut: async (identifier: string): Promise<OptOutEntry> => {
                try {
                    const result = await api.messaging.addOptOut(identifier, props.category?.key)
                    lemonToast.success(`${identifier} added to opt-out list`)
                    actions.loadOptOutPersons()
                    return result
                } catch (e) {
                    lemonToast.error('Failed to add opt-out')
                    throw e
                }
            },
        },
        optOutPersons: {
            __default: { count: 0, next: null, previous: null, results: [] } as PaginatedOptOuts,
            loadOptOutPersons: async (): Promise<PaginatedOptOuts> => {
                try {
                    return await api.messaging.getMessageOptOuts(props.category?.key, 1)
                } catch {
                    lemonToast.error('Failed to load opt-out persons')
                    return { count: 0, next: null, previous: null, results: [] }
                }
            },
            loadNextPage: async (): Promise<PaginatedOptOuts> => {
                const nextPage = values.currentPage + 1
                try {
                    const result = await api.messaging.getMessageOptOuts(props.category?.key, nextPage)
                    return result
                } catch {
                    lemonToast.error('Failed to load next page')
                    return values.optOutPersons
                }
            },
            loadPreviousPage: async (): Promise<PaginatedOptOuts> => {
                const prevPage = Math.max(1, values.currentPage - 1)
                try {
                    const result = await api.messaging.getMessageOptOuts(props.category?.key, prevPage)
                    return result
                } catch {
                    lemonToast.error('Failed to load previous page')
                    return values.optOutPersons
                }
            },
        },
        csvExport: {
            __default: null as null,
            exportCsv: async (): Promise<null> => {
                try {
                    const blob = await api.messaging.exportOptOutsCsv(props.category?.key)
                    downloadFile(new File([blob], `opt-outs-${props.category?.key ?? 'all-marketing'}.csv`))
                } catch {
                    lemonToast.error('Failed to export opt-outs')
                }
                return null
            },
        },
        csvImportResult: {
            __default: null as BulkAddOptOutsResultApi | null,
            clearCsvImportResult: (): BulkAddOptOutsResultApi | null => null,
            importCsv: async (): Promise<BulkAddOptOutsResultApi | null> => {
                const file = values.csvFile
                if (!file) {
                    return null
                }

                let rows: string[][]
                try {
                    rows = await parseCsvFile(file)
                } catch {
                    lemonToast.error("Couldn't read the file. Check that it's a valid CSV and try again.")
                    return null
                }

                const parsed = parseOptOutRows(rows)
                const result: BulkAddOptOutsResultApi = {
                    total: parsed.total,
                    opted_out: 0,
                    skipped: parsed.skipped,
                    errors: [...parsed.errors],
                }

                if (parsed.entries.length > 0) {
                    actions.setCsvImportProgress({ processed: 0, total: parsed.entries.length })
                }
                for (let start = 0; start < parsed.entries.length; start += BULK_OPT_OUT_CHUNK_SIZE) {
                    const chunk = parsed.entries.slice(start, start + BULK_OPT_OUT_CHUNK_SIZE)
                    try {
                        const chunkResult = await api.messaging.bulkAddOptOuts(
                            chunk.map(({ identifier, category_key }) => ({ identifier, category_key })),
                            props.category?.key
                        )
                        result.opted_out += chunkResult.opted_out
                        result.skipped += chunkResult.skipped
                        for (const error of remapEntryErrors(chunkResult.errors, chunk)) {
                            if (result.errors.length < MAX_REPORTED_ERRORS) {
                                result.errors.push(error)
                            }
                        }
                    } catch (e: any) {
                        // Already-applied chunks stay applied; re-uploading is safe because
                        // importing only ever opts recipients out.
                        const remaining = parsed.entries.length - start
                        result.errors.push(
                            e?.error ||
                                e?.detail ||
                                `The import stopped with ${remaining.toLocaleString()} recipients left. Upload the same file again to finish. Recipients that were already imported stay opted out.`
                        )
                        break
                    }
                    actions.setCsvImportProgress({
                        processed: Math.min(start + BULK_OPT_OUT_CHUNK_SIZE, parsed.entries.length),
                        total: parsed.entries.length,
                    })
                }

                if (result.opted_out > 0) {
                    lemonToast.success(`Added ${result.opted_out.toLocaleString()} opt-outs`)
                    actions.loadOptOutPersons()
                } else {
                    lemonToast.warning('No opt-outs were added. Check the file and try again.')
                }
                return result
            },
        },
    })),
    afterMount(({ props, actions }) => {
        // If no category is provided or it's a marketing category, load opt-out persons
        if (!props.category?.id || props.category?.category_type === 'marketing') {
            actions.loadOptOutPersons()
        }
    }),
])
