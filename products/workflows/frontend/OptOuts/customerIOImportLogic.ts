export const customerIOImportLogic = kea<customerIOImportLogicType>([
    path(['products', 'workflows', 'customerIOImportLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], preflightLogic, ['preflight']],
    })),
    actions({
        openImportModal: true,
        closeImportModal: true,
        resetImport: true,
        setImportError: (error: string | null) => ({ error }),
        toggleImportStep: (step: string) => ({ step }),
        setTrackedImportRunId: (runId: string | null) => ({ runId }),
        removeAppConfig: true,
        setCSVFile: (file: File | null) => ({ file }),
        uploadCSV: true,
        setCSVProgress: (csvProgress: CSVImportProgress | null) => ({ csvProgress }),
        setIsUploadingCSV: (isUploading: boolean) => ({ isUploading }),
        setWebhookSigningSecret: (secret: string) => ({ secret }),
        saveWebhookConfig: true,
        toggleWebhook: (enabled: boolean) => ({ enabled }),
        removeWebhookConfig: true,
        setIsSavingWebhook: (isSaving: boolean) => ({ isSaving }),
        setWebhookError: (error: string | null) => ({ error }),
        setTrackSiteId: (siteId: string) => ({ siteId }),
        setTrackApiKey: (apiKey: string) => ({ apiKey }),
        setTrackRegion: (region: string) => ({ region }),
        saveTrackConfig: true,
        toggleTrackSync: (enabled: boolean) => ({ enabled }),
        removeTrackConfig: true,
        setIsSavingTrack: (isSaving: boolean) => ({ isSaving }),
        setTrackError: (error: string | null) => ({ error }),
    }),
    loaders(({ values }) => ({
        syncConfig: [
            null as OptOutSyncConfigResponse | null,
            {
                loadSyncConfig: async () => {
                    return await new ApiRequest().messagingCategoriesOptOutSyncConfig().get()
                },
            },
        ],
        importRuns: [
            null as ProviderImportRunApi[] | null,
            {
                loadImportRuns: async () => {
                    const runs = await messagingProviderImportsList(String(values.currentTeamIdStrict))
                    return runs.filter((run) => run.provider === CUSTOMERIO_PROVIDER)
                },
            },
        ],
        importProviders: [
            null as ImportProviderOptionApi[] | null,
            {
                loadImportProviders: async () =>
                    await messagingProviderImportsProvidersList(String(values.currentTeamIdStrict)),
            },
        ],
        startedImportRun: [
            null as ProviderImportRunApi | null,
            {
                startImport: async ({ apiKey }: { apiKey: string | null }) =>
                    await messagingProviderImportsCreate(String(values.currentTeamIdStrict), {
                        provider: CUSTOMERIO_PROVIDER,
                        steps: values.selectedImportSteps,
                        ...(apiKey ? { api_key: apiKey } : {}),
                    }),
            },
        ],
    })),
    reducers({
        isImportModalOpen: [
            false,
            {
                openImportModal: () => true,
                closeImportModal: () => false,
            },
        ],
        importError: [
            null as string | null,
            {
                setImportError: (_, { error }) => error,
                startImport: () => null,
                startImportFailure: (_, { error, errorObject }) =>
                    errorObject?.detail ?? error ?? "Couldn't start the import. Check your API key and try again.",
                resetImport: () => null,
            },
        ],
        deselectedImportSteps: [
            [] as string[],
            {
                toggleImportStep: (deselected, { step }) =>
                    deselected.includes(step) ? deselected.filter((key) => key !== step) : [...deselected, step],
            },
        ],
        trackedImportRunId: [
            null as string | null,
            {
                setTrackedImportRunId: (_, { runId }) => runId,
                startImportSuccess: (_, { startedImportRun }) => startedImportRun.id,
            },
        ],
        csvFile: [
            null as File | null,
            {
                setCSVFile: (_, { file }) => file,
                resetImport: () => null,
                closeImportModal: () => null,
            },
        ],
        csvProgress: [
            null as CSVImportProgress | null,
            {
                setCSVProgress: (_, { csvProgress }) => csvProgress,
                resetImport: () => null,
                closeImportModal: () => null,
            },
        ],
        isUploadingCSV: [
            false,
            {
                setIsUploadingCSV: (_, { isUploading }) => isUploading,
                resetImport: () => false,
                closeImportModal: () => false,
            },
        ],
        isRemovingAppConfig: [
            false,
            {
                removeAppConfig: () => true,
                loadSyncConfigSuccess: () => false,
                loadSyncConfigFailure: () => false,
            },
        ],
        webhookSigningSecret: [
            '',
            {
                setWebhookSigningSecret: (_, { secret }) => secret,
                closeImportModal: () => '',
            },
        ],
        isSavingWebhook: [
            false,
            {
                setIsSavingWebhook: (_, { isSaving }) => isSaving,
            },
        ],
        webhookError: [
            null as string | null,
            {
                setWebhookError: (_, { error }) => error,
                saveWebhookConfig: () => null,
                toggleWebhook: () => null,
                removeWebhookConfig: () => null,
            },
        ],
        isRemovingWebhookConfig: [
            false,
            {
                removeWebhookConfig: () => true,
                loadSyncConfigSuccess: () => false,
                loadSyncConfigFailure: () => false,
            },
        ],
        trackSiteId: [
            '',
            {
                setTrackSiteId: (_, { siteId }) => siteId,
                closeImportModal: () => '',
            },
        ],
        trackApiKey: [
            '',
            {
                setTrackApiKey: (_, { apiKey }) => apiKey,
                closeImportModal: () => '',
            },
        ],
        trackRegion: [
            'US',
            {
                setTrackRegion: (_, { region }) => region,
            },
        ],
        isSavingTrack: [
            false,
            {
                setIsSavingTrack: (_, { isSaving }) => isSaving,
            },
        ],
        trackError: [
            null as string | null,
            {
                setTrackError: (_, { error }) => error,
                saveTrackConfig: () => null,
                toggleTrackSync: () => null,
                removeTrackConfig: () => null,
            },
        ],
        isRemovingTrackConfig: [
            false,
            {
                removeTrackConfig: () => true,
                loadSyncConfigSuccess: () => false,
                loadSyncConfigFailure: () => false,
            },
        ],
    }),
    forms(({ actions }) => ({
        importForm: {
            defaults: {
                app_api_key: '',
            } as ImportFormValues,
            submit: ({ app_api_key }) => {
                actions.startImport({ apiKey: app_api_key })
            },
        },
    })),
    selectors({
        latestImportRun: [
            (s) => [s.importRuns],
            (importRuns: ProviderImportRunApi[] | null): ProviderImportRunApi | null => importRuns?.[0] ?? null,
        ],
        isImportRunActive: [
            (s) => [s.latestImportRun],
            (latestImportRun: ProviderImportRunApi | null): boolean =>
                !!latestImportRun && ACTIVE_IMPORT_RUN_STATUSES.includes(latestImportRun.status),
        ],
        importStepOptions: [
            (s) => [s.importProviders],
            (importProviders: ImportProviderOptionApi[] | null): ImportStepOptionApi[] =>
                importProviders?.find((provider) => provider.key === CUSTOMERIO_PROVIDER)?.steps ?? [],
        ],
        selectedImportSteps: [
            (s) => [s.importStepOptions, s.deselectedImportSteps],
            (importStepOptions: ImportStepOptionApi[], deselectedImportSteps: string[]): string[] =>
                importStepOptions.map((step) => step.key).filter((key) => !deselectedImportSteps.includes(key)),
        ],
        webhookUrl: [
            (s) => [s.currentTeamIdStrict],
            (currentTeamIdStrict: number | string): string => {
                const host = window.location.origin
                return `${host}/api/projects/${currentTeamIdStrict}/messaging/customerio/webhook/`
            },
        ],
        stepCompletion: [
            (s) => [s.syncConfig, s.latestImportRun, s.csvProgress],
            (
                syncConfig: OptOutSyncConfigResponse | null,
                latestImportRun: ProviderImportRunApi | null,
                csvProgress: CSVImportProgress | null
            ): {
                step1: 'completed' | 'failed' | false
                step2: 'completed' | 'failed' | false
                step3: 'completed' | false
                step4: 'completed' | false
            } => {
                const resolveStatus = (
                    localStatus: string | undefined,
                    persistedStatus: string | undefined
                ): 'completed' | 'failed' | false => {
                    const status = localStatus || persistedStatus
                    if (status === 'completed' || status === 'failed') {
                        return status
                    }
                    return false
                }

                return {
                    step1: resolveStatus(latestImportRun?.status, syncConfig?.app_import_result?.status),
                    step2: resolveStatus(csvProgress?.status, syncConfig?.csv_import_result?.status),
                    step3: syncConfig?.webhook_enabled ? 'completed' : false,
                    step4: syncConfig?.track_enabled ? 'completed' : false,
                }
            },
        ],
        trackEnabled: [
            (s) => [s.syncConfig],
            (syncConfig: OptOutSyncConfigResponse | null): boolean => syncConfig?.track_enabled ?? false,
        ],
        hasTrackCredentials: [
            (s) => [s.syncConfig],
            (syncConfig: OptOutSyncConfigResponse | null): boolean => syncConfig?.has_track_credentials ?? false,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openImportModal: () => {
            actions.loadSyncConfig()
            actions.loadImportRuns()
            actions.loadImportProviders()
            actions.setTrackRegion(values.preflight?.region ?? 'US')
        },
        startImportSuccess: ({ startedImportRun }) => {
            // Show the new run at once, so a failed first refresh still shows progress and keeps polling.
            actions.loadImportRunsSuccess([
                startedImportRun,
                ...(values.importRuns ?? []).filter((run) => run.id !== startedImportRun.id),
            ])
            actions.resetImportForm()
            // The first start stores the API key, which the stored-key view reads from the sync config.
            actions.loadSyncConfig()
        },
        startImportFailure: ({ errorObject }) => {
            // A 409 means an import is already running, so show its progress instead of only an error.
            if (errorObject?.status === 409) {
                actions.loadImportRuns()
            }
        },
        loadImportRunsSuccess: ({ importRuns }) => {
            const latest = importRuns?.[0] ?? null
            if (latest && ACTIVE_IMPORT_RUN_STATUSES.includes(latest.status)) {
                actions.setTrackedImportRunId(latest.id)
                cache.disposables.add(() => {
                    const timeout = setTimeout(() => actions.loadImportRuns(), IMPORT_RUN_POLL_INTERVAL_MS)
                    return () => clearTimeout(timeout)
                }, 'importRunPoll')
                return
            }
            cache.disposables.dispose('importRunPoll')
            if (latest && latest.id === values.trackedImportRunId) {
                actions.setTrackedImportRunId(null)
                if (latest.status === 'completed') {
                    lemonToast.success('Customer.io import finished.')
                } else {
                    lemonToast.error('Some Customer.io import steps failed. Open the import to see which ones.')
                }
                optOutCategoriesLogic.findMounted()?.actions.loadCategories()
            }
        },
        loadImportRunsFailure: () => {
            // Keep polling through a failed request while an import is running, so one network error doesn't freeze the progress.
            if (values.trackedImportRunId) {
                cache.disposables.add(() => {
                    const timeout = setTimeout(() => actions.loadImportRuns(), IMPORT_RUN_POLL_INTERVAL_MS)
                    return () => clearTimeout(timeout)
                }, 'importRunPoll')
            }
        },
        removeAppConfig: async () => {
            try {
                await new ApiRequest().messagingCategoriesRemoveCustomerIOAppConfig().delete()
                actions.resetImport()
            } catch (error: any) {
                lemonToast.error(error.detail || 'Failed to remove integration')
            } finally {
                actions.loadSyncConfig()
            }
        },
        uploadCSV: async () => {
            const CSRF_COOKIE_NAME = 'posthog_csrftoken'
            const file = values.csvFile
            if (!file) {
                lemonToast.error('Please select a CSV file')
                return
            }

            actions.setIsUploadingCSV(true)
            actions.setCSVProgress(null) // Clear any previous progress

            const formData = new FormData()
            formData.append('csv_file', file)

            try {
                const response = await fetch(
                    `/api/projects/${values.currentTeamIdStrict}/messaging_categories/import_preferences_csv/`,
                    {
                        method: 'POST',
                        body: formData,
                        credentials: 'include',
                        headers: {
                            'X-CSRFToken': getCookie(CSRF_COOKIE_NAME) || '',
                        },
                    }
                )

                if (!response.ok) {
                    const errorText = await response.text()
                    throw new Error(errorText || `Upload failed with status ${response.status}`)
                }

                const data = await response.json()
                actions.setCSVProgress(data)

                if (data.status === 'completed') {
                    lemonToast.success('CSV import completed.')
                    actions.loadSyncConfig()
                    optOutCategoriesLogic.findMounted()?.actions.loadCategories()
                } else if (data.status === 'failed') {
                    lemonToast.error(data.details || 'CSV import failed')
                }
            } catch (error: any) {
                lemonToast.error(error.message || error.detail || 'Failed to upload CSV')
            } finally {
                actions.setIsUploadingCSV(false)
            }
        },
        saveWebhookConfig: async () => {
            const secret = values.webhookSigningSecret
            if (!secret) {
                actions.setWebhookError('Please enter a webhook signing secret.')
                return
            }
            actions.setIsSavingWebhook(true)
            try {
                await new ApiRequest().messagingCategoriesSaveWebhookConfig().create({
                    data: { webhook_signing_secret: secret, webhook_enabled: true },
                })
                lemonToast.success('Webhook sync enabled!')
                actions.setWebhookSigningSecret('')
                actions.loadSyncConfig()
            } catch (error: any) {
                actions.setWebhookError(error.detail || 'Failed to save webhook config')
            } finally {
                actions.setIsSavingWebhook(false)
            }
        },
        toggleWebhook: async ({ enabled }) => {
            actions.setIsSavingWebhook(true)
            try {
                await new ApiRequest().messagingCategoriesSaveWebhookConfig().create({
                    data: { webhook_enabled: enabled },
                })
                lemonToast.success(enabled ? 'Webhook sync enabled' : 'Webhook sync disabled')
                actions.loadSyncConfig()
            } catch (error: any) {
                actions.setWebhookError(error.detail || 'Failed to save webhook config')
            } finally {
                actions.setIsSavingWebhook(false)
            }
        },
        removeWebhookConfig: async () => {
            try {
                await new ApiRequest().messagingCategoriesRemoveWebhookConfig().delete()
                actions.setWebhookSigningSecret('')
            } catch (error: any) {
                lemonToast.error(error.detail || 'Failed to remove webhook integration')
            } finally {
                actions.loadSyncConfig()
            }
        },
        saveTrackConfig: async () => {
            const siteId = values.trackSiteId
            const apiKey = values.trackApiKey
            const region = values.trackRegion
            if (!siteId || !apiKey) {
                actions.setTrackError('Both site ID and API key are required.')
                return
            }
            actions.setIsSavingTrack(true)
            try {
                await new ApiRequest().messagingCategoriesSaveTrackConfig().create({
                    data: { site_id: siteId, api_key: apiKey, region, track_enabled: true },
                })
                lemonToast.success('Outbound sync enabled!')
                actions.setTrackSiteId('')
                actions.setTrackApiKey('')
                actions.loadSyncConfig()
            } catch (error: any) {
                actions.setTrackError(error.detail || 'Failed to save track config')
            } finally {
                actions.setIsSavingTrack(false)
            }
        },
        toggleTrackSync: async ({ enabled }) => {
            actions.setIsSavingTrack(true)
            try {
                await new ApiRequest().messagingCategoriesSaveTrackConfig().create({
                    data: { track_enabled: enabled },
                })
                lemonToast.success(enabled ? 'Outbound sync enabled' : 'Outbound sync disabled')
                actions.loadSyncConfig()
            } catch (error: any) {
                actions.setTrackError(error.detail || 'Failed to update track config')
            } finally {
                actions.setIsSavingTrack(false)
            }
        },
        removeTrackConfig: async () => {
            try {
                await new ApiRequest().messagingCategoriesRemoveTrackConfig().delete()
                actions.setTrackSiteId('')
                actions.setTrackApiKey('')
            } catch (error: any) {
                lemonToast.error(error.detail || 'Failed to remove track integration')
            } finally {
                actions.loadSyncConfig()
            }
        },
        closeImportModal: () => {
            actions.resetImportForm()
            actions.resetImport()
        },
    })),
])
