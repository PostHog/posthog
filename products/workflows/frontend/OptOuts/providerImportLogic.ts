export const providerImportLogic = kea<providerImportLogicType>([
    path(['products', 'workflows', 'providerImportLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
    })),
    actions({
        openImportModal: (providerKey: string | null = null) => ({ providerKey }),
        closeImportModal: true,
        selectProvider: (providerKey: string | null) => ({ providerKey }),
        resetImport: true,
        setImportError: (error: string | null) => ({ error }),
        toggleImportStep: (step: string) => ({ step }),
        setTrackedImportRunIds: (runIds: string[]) => ({ runIds }),
        setShowImportAgainForm: (show: boolean) => ({ show }),
    }),
    loaders(({ values }) => ({
        importRuns: [
            null as ProviderImportRunApi[] | null,
            {
                loadImportRuns: async () => await messagingProviderImportsList(String(values.currentTeamIdStrict)),
            },
        ],
        importProviders: [
            null as ImportProviderOptionApi[] | null,
            {
                loadImportProviders: async () =>
                    await messagingProviderImportsProvidersList(String(values.currentTeamIdStrict)),
            },
        ],
        startedImportRun: [
            null as ProviderImportRunApi | null,
            {
                startImport: async ({ apiKey }: { apiKey: string | null }) =>
                    await messagingProviderImportsCreate(String(values.currentTeamIdStrict), {
                        provider: values.selectedProvider?.key as ImportProviderOptionApi['key'],
                        steps: values.selectedImportSteps,
                        ...(apiKey ? { api_key: apiKey } : {}),
                    }),
            },
        ],
    })),
    reducers({
        isImportModalOpen: [
            false,
            {
                openImportModal: () => true,
                closeImportModal: () => false,
            },
        ],
        chosenProviderKey: [
            null as string | null,
            {
                openImportModal: (_, { providerKey }) => providerKey,
                selectProvider: (_, { providerKey }) => providerKey,
            },
        ],
        importError: [
            null as string | null,
            {
                setImportError: (_, { error }) => error,
                startImport: () => null,
                startImportFailure: (_, { error, errorObject }) =>
                    errorObject?.detail ?? error ?? "Couldn't start the import. Check your API key and try again.",
                resetImport: () => null,
                selectProvider: () => null,
            },
        ],
        deselectedImportSteps: [
            [] as string[],
            {
                toggleImportStep: (deselected, { step }) =>
                    deselected.includes(step) ? deselected.filter((key) => key !== step) : [...deselected, step],
                selectProvider: () => [],
            },
        ],
        trackedImportRunIds: [
            [] as string[],
            {
                setTrackedImportRunIds: (_, { runIds }) => runIds,
                startImportSuccess: (runIds, { startedImportRun }) => [...runIds, startedImportRun.id],
            },
        ],
        showImportAgainForm: [
            false,
            {
                setShowImportAgainForm: (_, { show }) => show,
                startImportSuccess: () => false,
                selectProvider: () => false,
                closeImportModal: () => false,
            },
        ],
    }),
    forms(({ actions }) => ({
        importForm: {
            defaults: {
                api_key: '',
            } as ImportFormValues,
            submit: ({ api_key }) => {
                actions.startImport({ apiKey: api_key })
            },
        },
    })),
    selectors({
        selectedProvider: [
            (s) => [s.importProviders, s.chosenProviderKey],
            (
                importProviders: ImportProviderOptionApi[] | null,
                chosenProviderKey: string | null
            ): ImportProviderOptionApi | null => {
                if (!importProviders) {
                    return null
                }
                // With one tool to choose from, a picker would only add a click.
                return importProviders.length === 1
                    ? importProviders[0]
                    : (importProviders.find((provider) => provider.key === chosenProviderKey) ?? null)
            },
        ],
        hasSeveralProviders: [
            (s) => [s.importProviders],
            (importProviders: ImportProviderOptionApi[] | null): boolean => (importProviders?.length ?? 0) > 1,
        ],
        latestImportRunByProvider: [
            (s) => [s.importRuns],
            (importRuns: ProviderImportRunApi[] | null): Record<string, ProviderImportRunApi> => {
                const latest: Record<string, ProviderImportRunApi> = {}
                for (const run of importRuns ?? []) {
                    latest[run.provider] ??= run
                }
                return latest
            },
        ],
        latestImportRun: [
            (s) => [s.latestImportRunByProvider, s.selectedProvider],
            (
                latestImportRunByProvider: Record<string, ProviderImportRunApi>,
                selectedProvider: ImportProviderOptionApi | null
            ): ProviderImportRunApi | null =>
                selectedProvider ? (latestImportRunByProvider[selectedProvider.key] ?? null) : null,
        ],
        isImportRunActive: [
            (s) => [s.latestImportRun],
            (latestImportRun: ProviderImportRunApi | null): boolean => !!latestImportRun && isActive(latestImportRun),
        ],
        importStepOptions: [
            (s) => [s.selectedProvider],
            (selectedProvider: ImportProviderOptionApi | null): ImportStepOptionApi[] => selectedProvider?.steps ?? [],
        ],
        selectedImportSteps: [
            (s) => [s.importStepOptions, s.deselectedImportSteps],
            (importStepOptions: ImportStepOptionApi[], deselectedImportSteps: string[]): string[] =>
                importStepOptions.map((step) => step.key).filter((key) => !deselectedImportSteps.includes(key)),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openImportModal: () => {
            actions.loadImportRuns()
            actions.loadImportProviders()
        },
        selectProvider: () => {
            // A key belongs to one tool, so it must not travel to the next one picked.
            actions.resetImportForm()
        },
        startImportSuccess: ({ startedImportRun }) => {
            // Show the new run at once, so a failed first refresh still shows progress and keeps polling.
            actions.loadImportRunsSuccess([
                startedImportRun,
                ...(values.importRuns ?? []).filter((run) => run.id !== startedImportRun.id),
            ])
            actions.resetImportForm()
        },
        startImportFailure: ({ errorObject }) => {
            // A 409 means an import is already running, so show its progress instead of only an error.
            if (errorObject?.status === 409) {
                actions.loadImportRuns()
            }
        },
        loadImportRunsSuccess: ({ importRuns }) => {
            const runs = importRuns ?? []
            const activeIds = runs.filter(isActive).map((run) => run.id)
            // Each run reports its own end, so a run finishing beside a longer one isn't missed.
            for (const run of runs) {
                if (values.trackedImportRunIds.includes(run.id) && !activeIds.includes(run.id)) {
                    const label = values.importProviders?.find((provider) => provider.key === run.provider)?.label
                    if (run.status === 'completed') {
                        lemonToast.success(`${label ?? 'The'} import finished.`)
                    } else {
                        lemonToast.error(`Some ${label ?? ''} import steps failed. Open the import to see which ones.`)
                    }
                    optOutCategoriesLogic.findMounted()?.actions.loadCategories()
                }
            }
            actions.setTrackedImportRunIds(activeIds)
            if (activeIds.length > 0) {
                cache.disposables.add(() => {
                    const timeout = setTimeout(() => actions.loadImportRuns(), IMPORT_RUN_POLL_INTERVAL_MS)
                    return () => clearTimeout(timeout)
                }, 'importRunPoll')
                return
            }
            cache.disposables.dispose('importRunPoll')
        },
        loadImportRunsFailure: () => {
            // Keep polling through a failed request while an import is running, so one network error doesn't freeze the progress.
            if (values.trackedImportRunIds.length > 0) {
                cache.disposables.add(() => {
                    const timeout = setTimeout(() => actions.loadImportRuns(), IMPORT_RUN_POLL_INTERVAL_MS)
                    return () => clearTimeout(timeout)
                }, 'importRunPoll')
            }
        },
        closeImportModal: () => {
            actions.resetImportForm()
            actions.resetImport()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadImportProviders()
    }),
])
