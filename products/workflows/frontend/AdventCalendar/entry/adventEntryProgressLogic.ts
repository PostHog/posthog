export type adventEntryProgressLogicType = MakeLogicType<
    adventEntryProgressLogicValues,
    adventEntryProgressLogicActions,
    Record<string, any>,
    adventEntryProgressLogicMeta
>

const REFRESH_MS = 60_000

function doorDayOf(phase: AdventEntryPhase): number {
    return phase.status === 'open' ? phase.day : phase.status === 'over' ? ADVENT_LAST_DAY : 0
}

export const adventEntryProgressLogic = kea<adventEntryProgressLogicType>([
    path(['products', 'workflows', 'frontend', 'AdventCalendar', 'entry', 'adventEntryProgressLogic']),
    connect(() => ({
        values: [userLogic, ['user']],
    })),
    actions({
        refresh: () => ({ now: new Date(), stored: storedProgressByUser() }),
    }),
    reducers(() => ({
        now: [new Date(), { refresh: (_, { now }) => now }],
        progressByUser: [
            null as Record<string, AdventProgress> | null,
            {
                refresh: (_, { stored }) => cleanProgressByUser(stored),
            },
        ],
    })),
    selectors({
        phase: [(s) => [s.now], (now: Date): AdventEntryPhase => adventEntryPhase(now)],
        doorDay: [(s) => [s.phase], (phase: AdventEntryPhase): number => doorDayOf(phase)],
        progress: [
            (s) => [s.progressByUser, s.user],
            (progressByUser: Record<string, AdventProgress> | null, user: UserType | null): AdventProgress | null =>
                progressByUser && user ? reachableProgress(progressByUser[user.uuid] ?? EMPTY_ADVENT_PROGRESS) : null,
        ],
        rewards: [
            (s) => [s.user],
            (user: UserType | null): AdventRewards | null => (user ? drawAdventRewards(user.uuid) : null),
        ],
        doors: [
            (s) => [s.progress, s.rewards, s.doorDay],
            (progress: AdventProgress | null, rewards: AdventRewards | null, doorDay: number): AdventDoor[] | null =>
                progress && rewards ? adventEntryDoors(progress, rewards, doorDay) : null,
        ],
        nextDoorDay: [
            (s) => [s.doors],
            (doors: AdventDoor[] | null): number | null => doors?.find((door) => door.status === 'ready')?.day ?? null,
        ],
    }),
    afterMount(({ actions, cache }) => {
        cache.disposables.add(() => {
            actions.refresh()
            const timer = window.setInterval(() => actions.refresh(), REFRESH_MS)
            const onStorage = (event: StorageEvent): void => {
                if (event.key === PROGRESS_STORAGE_KEY) {
                    actions.refresh()
                }
            }
            window.addEventListener('storage', onStorage)
            return () => {
                window.clearInterval(timer)
                window.removeEventListener('storage', onStorage)
            }
        }, 'refresh')
    }),
])
