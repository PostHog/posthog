import { connect, kea, MakeLogicType, path, selectors } from 'kea'
import { router } from 'kea-router'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic, FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { appLogic } from 'scenes/appLogic'
import { urls } from 'scenes/urls'

export type AdventCalendarAccess = 'unknown' | 'calendar' | 'denied'

const isCalendarRoute = (pathname: string): boolean => {
    try {
        return removeProjectIdIfPresent(decodeURI(pathname)).replace(/\/+$/, '') === urls.workflowsAdventCalendar()
    } catch {
        return false
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface adventCalendarAccessLogicValues {
    featureFlagsTimedOut: boolean // appLogic
    featureFlags: FeatureFlagsSet // featureFlagLogic
    receivedFeatureFlags: boolean // featureFlagLogic
    location: {
        pathname: string
        search: string
        hash: string
    } // router
    calendarAccess: AdventCalendarAccess
    onCalendarRoute: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface adventCalendarAccessLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        calendarAccess: (
            featureFlags: FeatureFlagsSet,
            receivedFeatureFlags: boolean,
            featureFlagsTimedOut: boolean
        ) => AdventCalendarAccess
        onCalendarRoute: (location: { hash: string; pathname: string; search: string }) => boolean
    }
}

export type adventCalendarAccessLogicType = MakeLogicType<
    adventCalendarAccessLogicValues,
    {},
    Record<string, any>,
    adventCalendarAccessLogicMeta
>

export const adventCalendarAccessLogic = kea<adventCalendarAccessLogicType>([
    path(['products', 'workflows', 'frontend', 'AdventCalendar', 'adventCalendarAccessLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags', 'receivedFeatureFlags'],
            appLogic,
            ['featureFlagsTimedOut'],
            router,
            ['location'],
        ],
    })),
    selectors({
        calendarAccess: [
            (s) => [s.featureFlags, s.receivedFeatureFlags, s.featureFlagsTimedOut],
            (
                featureFlags: adventCalendarAccessLogicValues['featureFlags'],
                receivedFeatureFlags: adventCalendarAccessLogicValues['receivedFeatureFlags'],
                featureFlagsTimedOut: adventCalendarAccessLogicValues['featureFlagsTimedOut']
            ): AdventCalendarAccess => {
                if (featureFlags[FEATURE_FLAGS.WORKFLOWS_ADVENT_CALENDAR]) {
                    return 'calendar'
                }
                return receivedFeatureFlags || featureFlagsTimedOut ? 'denied' : 'unknown'
            },
        ],
        onCalendarRoute: [
            (s) => [s.location],
            (location: adventCalendarAccessLogicValues['location']): boolean => isCalendarRoute(location.pathname),
        ],
    }),
])
