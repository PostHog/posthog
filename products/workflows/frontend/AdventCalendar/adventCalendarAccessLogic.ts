import { MakeLogicType, actions, afterMount, connect, kea, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic, type FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { appLogic } from 'scenes/appLogic'

const FLAG = FEATURE_FLAGS.WORKFLOWS_ADVENT_CALENDAR

const REQUEST_ERRORS = ['timeout', 'connection_error', 'unknown_error']

function isRequestError(error: unknown): boolean {
    return typeof error === 'string' && (REQUEST_ERRORS.includes(error) || error.startsWith('api_error_'))
}

function lastLoadFailedBeforeMount(): boolean {
    const errors = posthog.get_property('$feature_flag_errors')
    return (
        !!window.POSTHOG_GLOBAL_ERRORS?.onFeatureFlagsLoadError && Array.isArray(errors) && errors.some(isRequestError)
    )
}

function pageDecision(): boolean | undefined {
    const pageFlags = window.POSTHOG_USER_IDENTITY_WITH_FLAGS?.featureFlags
    if (!pageFlags) {
        return undefined
    }
    const decision = pageFlags[FLAG] ?? false
    return typeof decision === 'boolean' ? decision : undefined
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface adventCalendarAccessLogicValues {
    featureFlagsTimedOut: boolean // appLogic
    featureFlags: FeatureFlagsSet // featureFlagLogic
    receivedFeatureFlags: boolean // featureFlagLogic
    calendarOn: boolean | undefined
    lastLoadFailed: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface adventCalendarAccessLogicActions {
    setLastLoadFailed: (lastLoadFailed: boolean) => {
        lastLoadFailed: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface adventCalendarAccessLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        calendarOn: (
            featureFlags: FeatureFlagsSet,
            receivedFeatureFlags: boolean,
            featureFlagsTimedOut: boolean,
            lastLoadFailed: boolean
        ) => boolean | undefined
    }
}

export type adventCalendarAccessLogicType = MakeLogicType<
    adventCalendarAccessLogicValues,
    adventCalendarAccessLogicActions,
    Record<string, any>,
    adventCalendarAccessLogicMeta
>

export const adventCalendarAccessLogic = kea<adventCalendarAccessLogicType>([
    path(['products', 'workflows', 'frontend', 'AdventCalendar', 'adventCalendarAccessLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags', 'receivedFeatureFlags'], appLogic, ['featureFlagsTimedOut']],
    })),
    actions({
        setLastLoadFailed: (lastLoadFailed: boolean) => ({ lastLoadFailed }),
    }),
    reducers({
        lastLoadFailed: [
            false,
            {
                setLastLoadFailed: (_, { lastLoadFailed }) => lastLoadFailed,
            },
        ],
    }),
    selectors({
        calendarOn: [
            (s) => [s.featureFlags, s.receivedFeatureFlags, s.featureFlagsTimedOut, s.lastLoadFailed],
            (
                featureFlags: adventCalendarAccessLogicValues['featureFlags'],
                receivedFeatureFlags: adventCalendarAccessLogicValues['receivedFeatureFlags'],
                featureFlagsTimedOut: adventCalendarAccessLogicValues['featureFlagsTimedOut'],
                lastLoadFailed: adventCalendarAccessLogicValues['lastLoadFailed']
            ): boolean | undefined => {
                const decision = pageDecision()
                if (lastLoadFailed && decision !== undefined) {
                    return decision
                }
                if (!receivedFeatureFlags && !featureFlagsTimedOut) {
                    return undefined
                }
                return !!featureFlags[FLAG]
            },
        ],
    }),
    afterMount(({ actions, cache }) => {
        actions.setLastLoadFailed(lastLoadFailedBeforeMount())
        cache.disposables.add(
            () =>
                posthog.onFeatureFlags((_flags, _variants, context) => {
                    if (typeof context?.errorsLoading === 'boolean') {
                        actions.setLastLoadFailed(context.errorsLoading)
                    }
                }),
            'flagLoads',
            { pauseOnPageHidden: false }
        )
    }),
])
