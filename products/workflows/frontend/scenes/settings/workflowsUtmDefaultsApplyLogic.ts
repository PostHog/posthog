export interface workflowsUtmDefaultsApplyLogicValues {
    currentProjectId: number | null // projectLogic
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    applyResult: ApplyUtmDefaultsResponseApi | null
    applyResultLoading: boolean
    enableWhereOff: boolean
    isApplyDialogOpen: boolean
    preview: ApplyUtmDefaultsResponseApi | null
    previewLoading: boolean
}

