import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import { projectLogic } from 'scenes/projectLogic'
import { teamLogic } from 'scenes/teamLogic'

import type { TeamPublicType, TeamType } from '~/types'

import { hogFlowsApplyUtmDefaultsCreate } from '../../generated/api'
import type { ApplyUtmDefaultsResponseApi } from '../../generated/api.schemas'
import { getTeamUtmDefaults, matchesTeamUtmDefaults } from '../../Workflows/hogflows/steps/components/utmDefaults'
import type { UtmTagKey, UtmTagValues } from '../../Workflows/hogflows/steps/components/UtmTagFields'

