export const workflowsUtmDefaultsApplyLogic = kea<workflowsUtmDefaultsApplyLogicType>([
    path(['products', 'workflows', 'frontend', 'scenes', 'settings', 'workflowsUtmDefaultsApplyLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], teamLogic, ['currentTeam']],
    })),
    actions({
        setDraftEnabled: (enabled: boolean) => ({ enabled }),
        setDraftParams: (params: UtmTagValues) => ({ params }),
        resetDraft: true,
        saveDefaults: true,
        openApplyDialog: true,
        closeApplyDialog: true,
        setEnableWhereOff: (enableWhereOff: boolean) => ({ enableWhereOff }),
    }),
    reducers({
        // Null while the form shows the saved defaults, so a team that loads or changes later fills it in.
        draft: [
            null as Partial<TeamUtmDefaults> | null,
            {
                setDraftEnabled: (state, { enabled }) => ({ ...state, enabled }),
                setDraftParams: (state, { params }) => ({ ...state, params }),
                resetDraft: () => null,
            },
        ],
        isApplyDialogOpen: [
            false,
            {
                openApplyDialog: () => true,
                closeApplyDialog: () => false,
            },
        ],
        enableWhereOff: [
            false,
            {
                setEnableWhereOff: (_, { enableWhereOff }) => enableWhereOff,
                openApplyDialog: () => false,
            },
        ],
        // The loader keeps its last result when a reload fails, so a count only counts while it is current.
        isPreviewCurrent: [
            false,
            {
                loadPreview: () => false,
                loadPreviewSuccess: () => true,
            },
        ],
    }),
    selectors({
        savedDefaults: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): TeamUtmDefaults =>
                getTeamUtmDefaults(currentTeam?.workflows_config),
        ],
        form: [
            (s) => [s.draft, s.savedDefaults],
            (draft: Partial<TeamUtmDefaults> | null, saved: TeamUtmDefaults): TeamUtmDefaults => ({
                enabled: draft?.enabled ?? saved.enabled,
                params: draft?.params ?? saved.params,
            }),
        ],
        hasUnsavedChanges: [
            (s) => [s.form, s.savedDefaults],
            (form: TeamUtmDefaults, saved: TeamUtmDefaults): boolean =>
                form.enabled !== saved.enabled || !matchesTeamUtmDefaults(form.params, saved),
        ],
    }),
    loaders(({ values }) => ({
        preview: [
            null as ApplyUtmDefaultsResponseApi | null,
            {
                loadPreview: async () => {
                    return await hogFlowsApplyUtmDefaultsCreate(String(values.currentProjectId), {
                        dry_run: true,
                        enable_where_off: values.enableWhereOff,
                    })
                },
            },
        ],
        applyResult: [
            null as ApplyUtmDefaultsResponseApi | null,
            {
                applyDefaults: async () => {
                    return await hogFlowsApplyUtmDefaultsCreate(String(values.currentProjectId), {
                        dry_run: false,
                        enable_where_off: values.enableWhereOff,
                    })
                },
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        saveDefaults: async () => {
            const form = values.form
            const before = values.savedDefaults
            const offerApply = !matchesTeamUtmDefaults(form.params, before) || (form.enabled && !before.enabled)
            const params = cleanUtmParams(form.params)
            if (!values.currentTeam?.workflows_config) {
                return
            }
            await teamLogic.asyncActions.updateCurrentTeam({
                // The API updates only the fields sent. A copy of the cached config would overwrite newer settings.
                workflows_config: {
                    email_utm_tags_enabled: form.enabled,
                    email_utm_params: params,
                } satisfies Partial<WorkflowsConfig> as WorkflowsConfig,
            })
            // A failed save still resolves, so check what was saved. On failure the form keeps the edits.
            const saved = values.savedDefaults
            if (saved.enabled !== form.enabled || !matchesTeamUtmDefaults(params, saved)) {
                return
            }
            // Edits made while the save was in flight are not saved yet, so they stay in the form.
            if (values.form.enabled === form.enabled && matchesTeamUtmDefaults(values.form.params, saved)) {
                actions.resetDraft()
            }
            if (offerApply) {
                actions.openApplyDialog()
            }
        },
        openApplyDialog: () => actions.loadPreview(),
        setEnableWhereOff: () => actions.loadPreview(),
        applyDefaultsSuccess: ({ applyResult }) => {
            actions.closeApplyDialog()
            const skipped = (applyResult?.workflows_failed ?? 0) + (applyResult?.workflows_without_access ?? 0)
            if (skipped > 0) {
                lemonToast.warning(
                    `Updated ${applyResult?.emails_updated ?? 0} emails. ${skipped} workflows kept their old values.`
                )
            } else {
                lemonToast.success(`Updated ${applyResult?.emails_updated ?? 0} emails with the new defaults`)
            }
        },
        applyDefaultsFailure: () => {
            lemonToast.error("Couldn't update existing emails. Try again.")
        },
        loadPreviewFailure: () => {
            lemonToast.error("Couldn't count the emails to update. Try again.")
        },
    })),
])
