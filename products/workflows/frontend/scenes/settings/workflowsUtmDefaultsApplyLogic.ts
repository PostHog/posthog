export type workflowsUtmDefaultsApplyLogicType = MakeLogicType<
    workflowsUtmDefaultsApplyLogicValues,
    workflowsUtmDefaultsApplyLogicActions
>

export const workflowsUtmDefaultsApplyLogic = kea<workflowsUtmDefaultsApplyLogicType>([
    path(['products', 'workflows', 'frontend', 'scenes', 'settings', 'workflowsUtmDefaultsApplyLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], teamLogic, ['currentTeam']],
    })),
    actions({
        saveDefaults: (enabled: boolean, params: UtmTagValues, offerApply: boolean) => ({
            enabled,
            params,
            offerApply,
        }),
        openApplyDialog: true,
        closeApplyDialog: true,
        setEnableWhereOff: (enableWhereOff: boolean) => ({ enableWhereOff }),
    }),
    reducers({
        isApplyDialogOpen: [
            false,
            {
                openApplyDialog: () => true,
                closeApplyDialog: () => false,
            },
        ],
        enableWhereOff: [
            false,
            {
                setEnableWhereOff: (_, { enableWhereOff }) => enableWhereOff,
                openApplyDialog: () => false,
            },
        ],
    }),
    loaders(({ values }) => ({
        preview: [
            null as ApplyUtmDefaultsResponseApi | null,
            {
                loadPreview: async () => {
                    return await hogFlowsApplyUtmDefaultsCreate(String(values.currentProjectId), {
                        dry_run: true,
                        enable_where_off: values.enableWhereOff,
                    })
                },
            },
        ],
        applyResult: [
            null as ApplyUtmDefaultsResponseApi | null,
            {
                applyDefaults: async () => {
                    return await hogFlowsApplyUtmDefaultsCreate(String(values.currentProjectId), {
                        dry_run: false,
                        enable_where_off: values.enableWhereOff,
                    })
                },
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        saveDefaults: async ({ enabled, params, offerApply }) => {
            const config = values.currentTeam?.workflows_config
            await teamLogic.asyncActions.updateCurrentTeam({
                workflows_config: {
                    ...config,
                    capture_workflows_engagement_events: config?.capture_workflows_engagement_events ?? false,
                    email_utm_tags_enabled: enabled,
                    email_utm_params: params,
                },
            })
            // The preview reads the saved defaults, so it waits for the save. A failed save still resolves, so
            // check what was saved before offering to apply it.
            const saved = getTeamUtmDefaults(values.currentTeam?.workflows_config)
            if (offerApply && saved.enabled === enabled && matchesTeamUtmDefaults(params, saved)) {
                actions.openApplyDialog()
            }
        },
        openApplyDialog: () => actions.loadPreview(),
        setEnableWhereOff: () => actions.loadPreview(),
        applyDefaultsSuccess: ({ applyResult }) => {
            actions.closeApplyDialog()
            if (applyResult && applyResult.workflows_failed > 0) {
                lemonToast.warning(
                    `Updated ${applyResult.emails_updated} emails. ${applyResult.workflows_failed} workflows couldn't be saved and kept their old values.`
                )
            } else {
                lemonToast.success(`Updated ${applyResult?.emails_updated ?? 0} emails with the new defaults`)
            }
        },
        applyDefaultsFailure: () => {
            lemonToast.error("Couldn't update existing emails. Try again.")
        },
        loadPreviewFailure: () => {
            lemonToast.error("Couldn't count the emails to update. Try again.")
        },
    })),
])
