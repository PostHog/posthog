import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { teamLogic } from 'scenes/teamLogic'

import type { TeamPublicType, TeamType, WorkflowsConfig } from '../../../../../frontend/src/types'
import {
    cleanUtmParams,
    getTeamUtmDefaults,
    matchesTeamUtmDefaults,
    type TeamUtmDefaults,
} from '../../Workflows/hogflows/steps/components/utmDefaults'
import type { UtmTagValues } from '../../Workflows/hogflows/steps/components/UtmTagFields'
import type { UtmTagKey } from '../../Workflows/hogflows/steps/components/UtmTagFields'

