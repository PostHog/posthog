export const sendDayPickerLogic = kea<sendDayPickerLogicType>([
    props({} as BroadcastWizardLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'workflows', 'frontend', 'SendCalendar', 'sendDayPickerLogic', key]),
    connect((props: BroadcastWizardLogicProps) => ({
        values: [
            sendCalendarLogic,
            ['scheduledFlows', 'scheduledFlowsLoading', 'weekStartDay', 'loadFailed'],
            teamLogic,
            ['currentTeam'],
            broadcastWizardLogic(props),
            ['sendAt', 'effectiveTimezone', 'audienceProperties', 'emailSettings'],
        ],
        actions: [broadcastWizardLogic(props), ['setSendAt'], sendCalendarLogic, ['loadScheduledFlows']],
    })),
    actions({
        setAnchor: (anchor: string | null) => ({ anchor }),
        goForward: true,
        goBackward: true,
        pickDay: (day: string) => ({ day }),
        applySuggestion: true,
    }),
    reducers({
        // Null follows the picked day, or today. A date pins the month that the person moved to.
        anchor: [null as string | null, { setAnchor: (_, { anchor }) => anchor }],
    }),
    selectors({
        rule: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): SendingRule =>
                sendingRule(currentTeam && 'workflows_config' in currentTeam ? currentTeam.workflows_config : null),
        ],
        isTransactional: [
            (s) => [s.emailSettings],
            (emailSettings: BroadcastEmailSettings): boolean => emailSettings.messageCategoryType === 'transactional',
        ],
        draftAudience: [
            (s) => [s.audienceProperties],
            (audienceProperties: AnyPropertyFilter[]): SendAudience => audienceFromProperties(audienceProperties),
        ],
        timeOfDay: [
            (s) => [s.sendAt, s.effectiveTimezone],
            (sendAt: string | null, timezone: string): string =>
                sendAt ? dayjs(sendAt).tz(timezone).format('HH:mm:ss') : DEFAULT_TIME_OF_DAY,
        ],
        today: [(s) => [s.effectiveTimezone], (timezone: string): string => dayjs().tz(timezone).format('YYYY-MM-DD')],
        selectedDay: [
            (s) => [s.sendAt, s.effectiveTimezone],
            (sendAt: string | null, timezone: string): string | null =>
                sendAt ? dayjs(sendAt).tz(timezone).format('YYYY-MM-DD') : null,
        ],
        anchorDate: [
            (s) => [s.anchor, s.selectedDay, s.today],
            (anchor: string | null, selectedDay: string | null, today: string): string =>
                anchor ?? selectedDay ?? today,
        ],
        days: [
            (s) => [s.anchorDate, s.weekStartDay],
            (anchorDate: string, weekStartDay: number): string[] => calendarDays('month', anchorDate, weekStartDay),
        ],
        otherSends: [
            (s, p) => [s.scheduledFlows, s.days, s.effectiveTimezone, s.rule, p.id],
            (
                scheduledFlows: ScheduledEmailFlow[] | null,
                days: string[],
                timezone: string,
                rule: SendingRule,
                id: string
            ): CalendarSend[] => {
                const now = dayjs()
                const grid = calendarRange(days, timezone)
                // The suggestion looks ahead past the grid. Every day it checks counts the sends a full cap
                // window either side of it, so the range reaches one window past both ends.
                const firstChecked = grid.start.isBefore(now) ? grid.start : now
                const horizonEnd = now.add(SUGGESTION_HORIZON_DAYS + 1, 'day')
                const lastChecked = grid.end.isAfter(horizonEnd) ? grid.end : horizonEnd
                const range = {
                    start: firstChecked.subtract(rule.windowDays, 'day'),
                    end: lastChecked.add(rule.windowDays, 'day'),
                }
                return (scheduledFlows ?? [])
                    .filter((item) => item.flow.id !== id)
                    .flatMap((item) => calendarSendsForFlow(item, range, now))
                    .filter((send) => send.state !== 'paused' && send.state !== 'failed')
            },
        ],
        countingSends: [
            (s) => [s.otherSends, s.draftAudience, s.isTransactional],
            (otherSends: CalendarSend[], draftAudience: SendAudience, isTransactional: boolean): CalendarSend[] =>
                isTransactional ? [] : otherSends.filter((send) => countsTowardRule(send, draftAudience)),
        ],
        countingKeys: [
            (s) => [s.countingSends],
            (countingSends: CalendarSend[]): Record<string, boolean> =>
                Object.fromEntries(countingSends.map((send) => [send.key, true])),
        ],
        sendsByDay: [
            (s) => [s.otherSends, s.effectiveTimezone],
            (otherSends: CalendarSend[], timezone: string): Record<string, CalendarSend[]> =>
                groupSendsByDay(otherSends, timezone),
        ],
        crowdedDays: [
            (s) => [s.days, s.countingSends, s.timeOfDay, s.effectiveTimezone, s.rule],
            (
                days: string[],
                countingSends: CalendarSend[],
                timeOfDay: string,
                timezone: string,
                rule: SendingRule
            ): Record<string, boolean> =>
                Object.fromEntries(
                    days.map((day) => [
                        day,
                        crowdingSends(timeOnDay(day, timeOfDay, timezone), countingSends, rule).length > 0,
                    ])
                ),
        ],
        selectedCrowding: [
            (s) => [s.sendAt, s.countingSends, s.rule],
            (sendAt: string | null, countingSends: CalendarSend[], rule: SendingRule): CalendarSend[] =>
                sendAt ? crowdingSends(dayjs(sendAt), countingSends, rule) : [],
        ],
        suggestion: [
            (s) => [s.countingSends, s.timeOfDay, s.effectiveTimezone, s.rule, s.isTransactional],
            (
                countingSends: CalendarSend[],
                timeOfDay: string,
                timezone: string,
                rule: SendingRule,
                isTransactional: boolean
            ): dayjs.Dayjs | null =>
                isTransactional
                    ? null
                    : suggestSendTime({ timeOfDay, timezone, now: dayjs(), others: countingSends, rule }),
        ],
    }),
    listeners(({ actions, values }) => ({
        goForward: () => actions.setAnchor(shiftAnchor('month', values.anchorDate, 1)),
        goBackward: () => actions.setAnchor(shiftAnchor('month', values.anchorDate, -1)),
        pickDay: ({ day }) => {
            const at = timeOnDay(day, values.timeOfDay, values.effectiveTimezone)
            actions.setSendAt(at.toISOString())
            // pinned: analytics event name
            posthog.capture('broadcast send day picked', {
                source: 'calendar',
                crowded: values.crowdedDays[day] ?? false,
                rule_from_cap: values.rule.fromCap,
            })
        },
        applySuggestion: () => {
            if (!values.suggestion) {
                return
            }
            actions.setSendAt(values.suggestion.toISOString())
            actions.setAnchor(null)
            // pinned: analytics event name
            posthog.capture('broadcast send day picked', {
                source: 'suggestion',
                crowded: false,
                rule_from_cap: values.rule.fromCap,
            })
        },
    })),
])
