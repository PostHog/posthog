export type sendCalendarLogicType = MakeLogicType<
    sendCalendarLogicValues,
    sendCalendarLogicActions,
    Record<string, any>,
    sendCalendarLogicMeta
>

export const sendCalendarLogic = kea<sendCalendarLogicType>([
    path(['products', 'workflows', 'frontend', 'SendCalendar', 'sendCalendarLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], teamLogic, ['timezone', 'weekStartDay']],
    })),
    actions({
        setView: (view: CalendarView) => ({ view }),
        setTypeFilter: (typeFilter: CalendarTypeFilter) => ({ typeFilter }),
        setAnchor: (anchor: string | null) => ({ anchor }),
        goToToday: true,
        goForward: true,
        goBackward: true,
        reportSendOpened: (send: CalendarSend) => ({ send }),
    }),
    loaders(({ values }) => ({
        scheduledFlows: [
            null as ScheduledEmailFlow[] | null,
            {
                loadScheduledFlows: async () => {
                    const projectId = String(values.currentProjectId)
                    const pages = await Promise.all(
                        SCHEDULED_TRIGGER_TYPES.map((type) =>
                            hogFlowsList(projectId, {
                                status: 'active',
                                trigger: JSON.stringify({ type }),
                                limit: FLOWS_LIMIT,
                            })
                        )
                    )
                    const flows = pages.flatMap((page) => page.results).filter(isScheduledEmailFlow)
                    const loaded: ScheduledEmailFlow[] = []
                    for (let index = 0; index < flows.length; index += FLOWS_PER_GROUP) {
                        const group = await Promise.all(
                            flows.slice(index, index + FLOWS_PER_GROUP).map(async (flow) => {
                                // A schedule trigger runs without a batch job, so only batch triggers have runs to show.
                                const isBatch = (flow.trigger as { type?: string } | null)?.type === 'batch'
                                const [schedules, batchJobs] = await Promise.all([
                                    hogFlowsSchedulesList(projectId, flow.id),
                                    isBatch ? hogFlowsBatchJobsList(projectId, flow.id) : Promise.resolve([]),
                                ])
                                return { flow, schedules, batchJobs }
                            })
                        )
                        loaded.push(...group)
                    }
                    return loaded
                },
            },
        ],
    })),
    reducers({
        view: ['month' as CalendarView, { setView: (_, { view }) => view }],
        typeFilter: ['all' as CalendarTypeFilter, { setTypeFilter: (_, { typeFilter }) => typeFilter }],
        // Null follows today. A date pins the period that the person moved to.
        anchor: [
            null as string | null,
            {
                setAnchor: (_, { anchor }) => anchor,
                goToToday: () => null,
            },
        ],
        loadFailed: [
            false,
            {
                loadScheduledFlows: () => false,
                loadScheduledFlowsFailure: () => true,
            },
        ],
    }),
    selectors({
        today: [(s) => [s.timezone], (timezone: string): string => dayjs().tz(timezone).format('YYYY-MM-DD')],
        anchorDate: [(s) => [s.anchor, s.today], (anchor: string | null, today: string): string => anchor ?? today],
        days: [
            (s) => [s.view, s.anchorDate, s.weekStartDay],
            (view: CalendarView, anchorDate: string, weekStartDay: number): string[] =>
                calendarDays(view, anchorDate, weekStartDay),
        ],
        range: [
            (s) => [s.days, s.timezone],
            (days: string[], timezone: string): CalendarRange => calendarRange(days, timezone),
        ],
        periodLabel: [
            (s) => [s.view, s.anchorDate, s.days],
            (view: CalendarView, anchorDate: string, days: string[]): string => periodLabel(view, anchorDate, days),
        ],
        sends: [
            (s) => [s.scheduledFlows, s.range, s.typeFilter],
            (
                scheduledFlows: ScheduledEmailFlow[] | null,
                range: CalendarRange,
                typeFilter: CalendarTypeFilter
            ): CalendarSend[] => {
                const now = dayjs()
                return (scheduledFlows ?? [])
                    .filter((item) => matchesTypeFilter(item.flow, typeFilter))
                    .flatMap((item) => calendarSendsForFlow(item, range, now))
            },
        ],
        sendsByDay: [
            (s) => [s.sends, s.timezone],
            (sends: CalendarSend[], timezone: string): Record<string, CalendarSend[]> =>
                groupSendsByDay(sends, timezone),
        ],
    }),
    listeners(({ actions, values }) => ({
        goForward: () => actions.setAnchor(shiftAnchor(values.view, values.anchorDate, 1)),
        goBackward: () => actions.setAnchor(shiftAnchor(values.view, values.anchorDate, -1)),
        loadScheduledFlowsSuccess: ({ scheduledFlows }) => {
            // pinned: analytics event name
            posthog.capture('send calendar viewed', {
                view: values.view,
                scheduled_flows: scheduledFlows?.length ?? 0,
                sends_in_range: values.sends.length,
            })
        },
        setView: ({ view }) => {
            // pinned: analytics event name
            posthog.capture('send calendar viewed', {
                view,
                scheduled_flows: values.scheduledFlows?.length ?? 0,
                sends_in_range: values.sends.length,
            })
        },
        reportSendOpened: ({ send }) => {
            // pinned: analytics event name
            posthog.capture('send calendar send opened', {
                kind: send.kind,
                state: send.state,
                is_recurring: send.isRecurring,
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadScheduledFlows()
    }),
])
