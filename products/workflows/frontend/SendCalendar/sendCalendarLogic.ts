const SCHEDULE_CHANGED = 'Its schedule changed after the calendar loaded. Check the reloaded calendar and try again.'

/** False when the schedule changed after the calendar loaded it. A move saves the whole rule, so it would undo that change. */
async function scheduleIsCurrent(projectId: string, flowId: string, schedule: HogFlowScheduleApi): Promise<boolean> {
    const current = (await hogFlowsSchedulesList(projectId, flowId)).find((item) => item.id === schedule.id)
    return (
        !!current &&
        current.rrule === schedule.rrule &&
        dayjs(current.starts_at).isSame(schedule.starts_at) &&
        current.timezone === schedule.timezone &&
        current.status === schedule.status
    )
}

