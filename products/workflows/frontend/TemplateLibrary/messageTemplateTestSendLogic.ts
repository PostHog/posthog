export const messageTemplateTestSendLogic = kea<messageTemplateTestSendLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'TemplateLibrary', 'messageTemplateTestSendLogic', key]),
    props({} as MessageTemplateLogicProps),
    key(({ id }) => id ?? 'new'),
    connect((props: MessageTemplateLogicProps) => ({
        values: [
            messageTemplateLogic(props),
            ['template'],
            userLogic,
            ['user'],
            teamLogic,
            ['currentTeamId'],
            integrationsLogic,
            ['integrations', 'integrationsLoading'],
        ],
    })),
    actions({
        setPreviewDistinctId: (distinctId: string | null) => ({ distinctId }),
        setVariables: (variables: string) => ({ variables }),
        setModalOpen: (open: boolean) => ({ open }),
        setRecipientEmail: (email: string) => ({ email }),
        setSenderIntegrationId: (id: number | null) => ({ id }),
        clearTestSendResult: true,
    }),
    reducers({
        previewDistinctId: [null as string | null, { setPreviewDistinctId: (_, { distinctId }) => distinctId }],
        variables: ['{}', { setVariables: (_, { variables }) => variables }],
        isModalOpen: [false, { setModalOpen: (_, { open }) => open }],
        recipientEmail: ['', { setRecipientEmail: (_, { email }) => email }],
        senderIntegrationIdOverride: [null as number | null, { setSenderIntegrationId: (_, { id }) => id }],
    }),
    loaders(({ values }) => ({
        previewPerson: [
            null as PersonListRecordApi | null,
            {
                setPreviewDistinctId: async ({ distinctId }, breakpoint): Promise<PersonListRecordApi | null> => {
                    if (!distinctId) {
                        return null
                    }
                    if (!values.currentTeamId) {
                        throw new Error('Choose a project before selecting a person')
                    }
                    const response = await personsList(String(values.currentTeamId), {
                        distinct_id: distinctId,
                        limit: 1,
                    })
                    breakpoint()
                    if (!response.results?.[0]) {
                        throw new Error('Person not found. Choose another person.')
                    }
                    return response.results[0]
                },
            },
        ],
        testSendResult: [
            null as HogflowTestResult | null,
            {
                clearTestSendResult: () => null,
                sendTestEmail: async (): Promise<HogflowTestResult> => {
                    if (values.variablesError || values.previewPersonDisabledReason) {
                        throw new Error(values.sendDisabledReason)
                    }
                    const { template, recipientEmail, senderIntegrationId, currentTeamId } = values
                    posthog.capture('workflow template test send started', {
                        has_preview_person: !!values.previewDistinctId,
                        has_variable_overrides: Object.keys(parseTestVariables(values.variables)).length > 0,
                    })

                    const emailAction: HogFlowAction = {
                        id: TEST_EMAIL_ACTION_ID,
                        type: 'function_email',
                        name: 'Send test email',
                        description: '',
                        created_at: 0,
                        updated_at: 0,
                        config: {
                            template_id: 'template-email',
                            inputs: {
                                email: {
                                    value: {
                                        ...template.content.email,
                                        // A test send has exactly one visible recipient - never carry over a
                                        // cc/bcc that happened to be on the copied source content.
                                        cc: '',
                                        bcc: '',
                                        // A custom name and address carry over, so the test shows what a send shows.
                                        from: {
                                            ...senderFrom(template.content.email ?? {}),
                                            integrationIds: undefined,
                                            integrationId: senderIntegrationId ?? undefined,
                                        },
                                        to: { email: recipientEmail, name: '' },
                                    },
                                    templating: template.content.templating === 'hog' ? 'hog' : 'liquid',
                                },
                            },
                        },
                    }

                    const edges: HogFlowEdge[] = [
                        { from: TRIGGER_NODE_ID, to: TEST_EMAIL_ACTION_ID, type: 'continue' },
                        { from: TEST_EMAIL_ACTION_ID, to: EXIT_NODE_ID, type: 'continue' },
                    ]

                    const configuration: HogFlow = {
                        ...NEW_WORKFLOW,
                        team_id: currentTeamId ?? NEW_WORKFLOW.team_id,
                        name: template.name || 'Test email',
                        actions: [NEW_WORKFLOW.actions[0], emailAction, NEW_WORKFLOW.actions[1]],
                        edges,
                    }

                    // The generated invocation client returns void, so use its URL with the test response type.
                    return await apiMutator<HogflowTestResult>(
                        getHogFlowsInvocationsCreateUrl(String(ApiConfig.getCurrentTeamId()), 'new'),
                        {
                            method: 'POST',
                            body: JSON.stringify({
                                configuration,
                                globals: values.testGlobals,
                                mock_async_functions: false,
                                current_action_id: TEST_EMAIL_ACTION_ID,
                            }),
                        }
                    )
                },
            },
        ],
    })),
    selectors({
        previewPersonDisabledReason: [
            (s) => [s.previewDistinctId, s.previewPerson, s.previewPersonLoading],
            (distinctId: string | null, person: PersonListRecordApi | null, loading: boolean): string | undefined => {
                if (loading) {
                    return 'Loading preview person'
                }
                if (distinctId && !person?.distinct_ids.includes(distinctId)) {
                    return 'Choose a person whose properties could be loaded, or clear the selection'
                }
            },
        ],
        variablesError: [
            (s) => [s.variables],
            (variables: string): string | undefined => testVariablesError(variables),
        ],
        testGlobals: [
            (s) => [s.currentTeamId, s.template, s.recipientEmail, s.previewDistinctId, s.previewPerson, s.variables],
            (
                currentTeamId: number | null,
                template: MessageTemplate,
                recipientEmail: string,
                distinctId: string | null,
                person: PersonListRecordApi | null,
                variables: string
            ): CyclotronJobInvocationGlobals => {
                const globals = createExampleEvent(
                    currentTeamId ?? undefined,
                    template.name,
                    '$pageview',
                    recipientEmail
                )
                if (distinctId && person?.distinct_ids.includes(distinctId)) {
                    globals.event.distinct_id = distinctId
                    globals.person = {
                        id: person.uuid,
                        properties:
                            person.properties &&
                            typeof person.properties === 'object' &&
                            !Array.isArray(person.properties)
                                ? (person.properties as Record<string, any>)
                                : {},
                        name: person.name,
                        url: `${window.location.origin}/project/${currentTeamId}/person/${person.uuid}`,
                    }
                }
                return { ...globals, variables: testVariablesError(variables) ? {} : parseTestVariables(variables) }
            },
        ],
        previewEmail: [
            (s) => [s.template, s.testGlobals, s.variablesError, s.previewDistinctId, s.previewPerson],
            (
                template: MessageTemplate,
                globals: CyclotronJobInvocationGlobals,
                variablesError: string | undefined,
                distinctId: string | null,
                person: PersonListRecordApi | null
            ): { subject: string; html: string; text: string; error?: string } => {
                if (variablesError) {
                    return { subject: '', html: '', text: '', error: variablesError }
                }
                if (distinctId && !person?.distinct_ids.includes(distinctId)) {
                    return {
                        subject: '',
                        html: '',
                        text: '',
                        error: 'Could not load this person. Choose another person or clear the selection.',
                    }
                }
                if (template.content.templating === 'hog') {
                    return { subject: '', html: '', text: '', error: 'Use a test send to preview Hog templates.' }
                }
                try {
                    const render = (value?: string): string => LiquidRenderer.render(value ?? '', globals)
                    return {
                        subject: render(template.content.email?.subject),
                        html: render(template.content.email?.html),
                        text: render(template.content.email?.text),
                    }
                } catch {
                    return {
                        subject: '',
                        html: '',
                        text: '',
                        error: 'Could not preview this template. Check its Liquid expressions.',
                    }
                }
            },
        ],
        emailIntegrations: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): IntegrationType[] =>
                integrations?.filter(
                    (integration) => integration.kind === 'email' && integration.config?.verified === true
                ) ?? [],
        ],
        senderIntegrationId: [
            (s) => [s.senderIntegrationIdOverride, s.emailIntegrations, s.template],
            (override: number | null, emailIntegrations: IntegrationType[], template: MessageTemplate): number | null =>
                override ??
                senderIntegrationFor(template.content.email ?? {}, emailIntegrations)?.id ??
                emailIntegrations[0]?.id ??
                null,
        ],
        testSendSkipReason: [
            (s) => [s.testSendResult],
            (testSendResult: HogflowTestResult | null): string | undefined =>
                findTestSendSkipReason(testSendResult) ??
                (testSendResult?.status === 'skipped'
                    ? testSendResult.logs?.map((log) => log.message).join(' ') ||
                      'The send was skipped for this recipient.'
                    : undefined),
        ],
        sendDisabledReason: [
            (s) => [
                s.template,
                s.recipientEmail,
                s.senderIntegrationId,
                s.variablesError,
                s.previewPersonDisabledReason,
            ],
            (
                template: MessageTemplate,
                recipientEmail: string,
                senderIntegrationId: number | null,
                variablesError: string | undefined,
                previewPersonDisabledReason: string | undefined
            ): string | undefined => {
                if (variablesError) {
                    return variablesError
                }
                if (previewPersonDisabledReason) {
                    return previewPersonDisabledReason
                }
                if (!template.content.email?.subject) {
                    return 'Add a subject first'
                }
                if (!template.content.email.text && !template.content.email.html) {
                    return 'Add email content first'
                }
                if (!recipientEmail || !isEmail(recipientEmail)) {
                    return 'Enter a valid email address'
                }
                if (!senderIntegrationId) {
                    return 'Connect an email sender first'
                }
                return undefined
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setModalOpen: ({ open }) => {
            if (!open) {
                return
            }
            actions.clearTestSendResult()
            posthog.capture('workflow template test opened')
            if (!values.recipientEmail && values.user?.email) {
                actions.setRecipientEmail(values.user.email)
            }
        },
        sendTestEmailSuccess: ({ testSendResult }) => {
            posthog.capture('workflow template test sent', { status: testSendResult.status })
            if (values.testSendSkipReason) {
                lemonToast.warning('Test email skipped, see details below')
            } else if (testSendResult.status === 'success') {
                lemonToast.success(`Test email sent to ${values.recipientEmail}`)
                actions.setModalOpen(false)
                actions.clearTestSendResult()
            } else {
                lemonToast.error('Failed to send test email')
            }
        },
        sendTestEmailFailure: () => {
            posthog.capture('workflow template test sent', { status: 'error' })
            lemonToast.error('Failed to send test email')
        },
    })),
])
