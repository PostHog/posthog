export const messageTemplateTestSendLogic = kea<messageTemplateTestSendLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'TemplateLibrary', 'messageTemplateTestSendLogic', key]),
    props({} as MessageTemplateLogicProps),
    key(({ id }) => id ?? 'new'),
    connect((props: MessageTemplateLogicProps) => ({
        values: [
            messageTemplateLogic(props),
            ['template'],
            userLogic,
            ['user'],
            teamLogic,
            ['currentTeamId'],
            integrationsLogic,
            ['integrationsLoading', 'ownEmailIntegrations', 'sandboxEmailSender', 'sandboxEmailSenderEnabled'],
            membersLogic,
            ['members', 'membersLoading', 'meFirstMembers'],
        ],
        actions: [membersLogic, ['loadAllMembers']],
    })),
    actions({
        setModalOpen: (open: boolean) => ({ open }),
        setRecipientEmail: (email: string) => ({ email }),
        setSenderIntegrationId: (id: number | null) => ({ id }),
        clearTestSendResult: true,
    }),
    reducers({
        isModalOpen: [false, { setModalOpen: (_, { open }) => open }],
        recipientEmail: ['', { setRecipientEmail: (_, { email }) => email }],
        senderIntegrationIdOverride: [null as number | null, { setSenderIntegrationId: (_, { id }) => id }],
    }),
    loaders(({ values }) => ({
        testSendResult: [
            null as HogflowTestResult | null,
            {
                clearTestSendResult: () => null,
                sendTestEmail: async (): Promise<HogflowTestResult> => {
                    const { template, recipientEmail, senderIntegrationId, currentTeamId, isSandboxSenderSelected } =
                        values

                    const emailAction: HogFlowAction = {
                        id: TEST_EMAIL_ACTION_ID,
                        type: 'function_email',
                        name: 'Send test email',
                        description: '',
                        created_at: 0,
                        updated_at: 0,
                        config: {
                            template_id: 'template-email',
                            inputs: {
                                email: {
                                    value: {
                                        ...template.content.email,
                                        // A test send has exactly one visible recipient - never carry over a
                                        // cc/bcc that happened to be on the copied source content.
                                        cc: '',
                                        bcc: '',
                                        ...(isSandboxSenderSelected ? { replyTo: '' } : {}),
                                        // A custom name and address carry over, so the test shows what a send shows.
                                        // The sandbox sender ignores them and always sends from its fixed identity.
                                        from: isSandboxSenderSelected
                                            ? { integrationId: senderIntegrationId ?? undefined }
                                            : {
                                                  ...senderFrom(template.content.email ?? {}),
                                                  integrationIds: undefined,
                                                  integrationId: senderIntegrationId ?? undefined,
                                              },
                                        to: { email: recipientEmail, name: '' },
                                    },
                                    templating: template.content.templating === 'hog' ? 'hog' : 'liquid',
                                },
                            },
                        },
                    }

                    const edges: HogFlowEdge[] = [
                        { from: TRIGGER_NODE_ID, to: TEST_EMAIL_ACTION_ID, type: 'continue' },
                        { from: TEST_EMAIL_ACTION_ID, to: EXIT_NODE_ID, type: 'continue' },
                    ]

                    const configuration: HogFlow = {
                        ...NEW_WORKFLOW,
                        team_id: currentTeamId ?? NEW_WORKFLOW.team_id,
                        name: template.name || 'Test email',
                        actions: [NEW_WORKFLOW.actions[0], emailAction, NEW_WORKFLOW.actions[1]],
                        edges,
                    }

                    return await api.hogFlows.createTestInvocation('new', {
                        configuration,
                        globals: createExampleEvent(
                            currentTeamId ?? undefined,
                            configuration.name,
                            '$pageview',
                            recipientEmail
                        ),
                        mock_async_functions: false,
                        current_action_id: TEST_EMAIL_ACTION_ID,
                    })
                },
            },
        ],
    })),
    selectors({
        emailIntegrations: [
            (s) => [s.ownEmailIntegrations, s.sandboxEmailSender],
            (
                ownEmailIntegrations: IntegrationType[],
                sandboxEmailSender: IntegrationType | null
            ): IntegrationType[] => {
                const verifiedOwnSenders = ownEmailIntegrations.filter(
                    (integration) => integration.config?.verified === true
                )
                return sandboxEmailSender ? [...verifiedOwnSenders, sandboxEmailSender] : verifiedOwnSenders
            },
        ],
        senderIntegrationId: [
            (s) => [s.senderIntegrationIdOverride, s.emailIntegrations, s.template],
            (override: number | null, emailIntegrations: IntegrationType[], template: MessageTemplate): number | null =>
                emailIntegrations.find((integration) => integration.id === override)?.id ??
                senderIntegrationFor(template.content.email ?? {}, emailIntegrations)?.id ??
                emailIntegrations[0]?.id ??
                null,
        ],
        membersNeeded: [
            (s) => [s.isModalOpen, s.sandboxEmailSenderEnabled],
            (isModalOpen: boolean, sandboxEmailSenderEnabled: boolean): boolean =>
                isModalOpen && sandboxEmailSenderEnabled,
        ],
        isSandboxSenderSelected: [
            (s) => [s.senderIntegrationId, s.sandboxEmailSender],
            (senderIntegrationId: number | null, sandboxEmailSender: IntegrationType | null): boolean =>
                sandboxEmailSender !== null && senderIntegrationId === sandboxEmailSender.id,
        ],
        recipientSuggestions: [
            (s) => [s.meFirstMembers],
            (meFirstMembers: OrganizationMemberType[]): string[] =>
                meFirstMembers
                    .filter((member) => member.user.is_email_verified === true)
                    .map((member) => member.user.email),
        ],
        recipientIsUnverifiedSelf: [
            (s) => [s.isSandboxSenderSelected, s.recipientEmail, s.user],
            (isSandboxSenderSelected: boolean, recipientEmail: string, user: UserType | null): boolean =>
                isSandboxSenderSelected &&
                !!user &&
                user.is_email_verified !== true &&
                sameEmail(user.email, recipientEmail),
        ],
        recipientNotSuggested: [
            (s) => [s.isSandboxSenderSelected, s.recipientEmail, s.members, s.recipientSuggestions],
            (
                isSandboxSenderSelected: boolean,
                recipientEmail: string,
                members: OrganizationMemberType[] | null,
                recipientSuggestions: string[]
            ): boolean =>
                isSandboxSenderSelected &&
                members !== null &&
                isEmail(recipientEmail) &&
                !recipientSuggestions.some((suggestion) => sameEmail(suggestion, recipientEmail)),
        ],
        sendDisabledReason: [
            (s) => [s.template, s.recipientEmail, s.senderIntegrationId, s.isSandboxSenderSelected, s.membersLoading],
            (
                template: MessageTemplate,
                recipientEmail: string,
                senderIntegrationId: number | null,
                isSandboxSenderSelected: boolean,
                membersLoading: boolean
            ): string | undefined => {
                if (!template.content.email?.subject) {
                    return 'Add a subject first'
                }
                if (!template.content.email.text && !template.content.email.html) {
                    return 'Add email content first'
                }
                if (!recipientEmail || !isEmail(recipientEmail)) {
                    return 'Enter a valid email address'
                }
                if (!senderIntegrationId) {
                    return 'Connect an email sender first'
                }
                if (isSandboxSenderSelected && membersLoading) {
                    return 'Checking your organization members'
                }
                return undefined
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setModalOpen: ({ open }) => {
            if (!open) {
                return
            }
            actions.clearTestSendResult()
            if (!values.sandboxEmailSenderEnabled && !values.recipientEmail && values.user?.email) {
                actions.setRecipientEmail(values.user.email)
            }
        },
        sendTestEmailSuccess: ({ testSendResult }) => {
            if (testSendResult.status === 'success') {
                lemonToast.success(`Test email sent to ${values.recipientEmail}`)
                actions.setModalOpen(false)
                actions.clearTestSendResult()
            } else if (testSendResult.status === 'skipped') {
                lemonToast.warning('Test email skipped, see details below')
            } else {
                lemonToast.error('Failed to send test email')
            }
        },
        sendTestEmailFailure: () => {
            lemonToast.error('Failed to send test email')
        },
    })),
    subscriptions(({ actions }) => ({
        membersNeeded: (membersNeeded: boolean, wereNeeded: boolean | undefined) => {
            if (membersNeeded && !wereNeeded) {
                actions.loadAllMembers()
            }
        },
    })),
])
