export const messageTemplateTestSendLogic = kea<messageTemplateTestSendLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'TemplateLibrary', 'messageTemplateTestSendLogic', key]),
    props({} as MessageTemplateLogicProps),
    key(({ id }) => id ?? 'new'),
    connect((props: MessageTemplateLogicProps) => ({
        values: [
            messageTemplateLogic(props),
            ['template'],
            userLogic,
            ['user'],
            teamLogic,
            ['currentTeamId'],
            integrationsLogic,
            ['integrations', 'integrationsLoading'],
        ],
    })),
    actions({
        setModalOpen: (open: boolean) => ({ open }),
        setRecipientEmail: (email: string) => ({ email }),
        setSenderIntegrationId: (id: number | null) => ({ id }),
        clearTestSendResult: true,
    }),
    reducers({
        isModalOpen: [false, { setModalOpen: (_, { open }) => open }],
        recipientEmail: ['', { setRecipientEmail: (_, { email }) => email }],
        senderIntegrationIdOverride: [null as number | null, { setSenderIntegrationId: (_, { id }) => id }],
    }),
    loaders(({ values }) => ({
        testSendResult: [
            null as HogflowTestResult | null,
            {
                clearTestSendResult: () => null,
                sendTestEmail: async (): Promise<HogflowTestResult> => {
                    const { template, recipientEmail, senderIntegrationId, currentTeamId } = values

                    const emailAction: HogFlowAction = {
                        id: TEST_EMAIL_ACTION_ID,
                        type: 'function_email',
                        name: 'Send test email',
                        description: '',
                        created_at: 0,
                        updated_at: 0,
                        config: {
                            template_id: 'template-email',
                            inputs: {
                                email: {
                                    value: {
                                        ...template.content.email,
                                        // A test send has exactly one visible recipient - never carry over a
                                        // cc/bcc that happened to be on the copied source content.
                                        cc: '',
                                        bcc: '',
                                        from: { integrationId: senderIntegrationId ?? undefined },
                                        to: { email: recipientEmail, name: '' },
                                    },
                                    templating: template.content.templating === 'hog' ? 'hog' : 'liquid',
                                },
                            },
                        },
                    }

                    const edges: HogFlowEdge[] = [
                        { from: TRIGGER_NODE_ID, to: TEST_EMAIL_ACTION_ID, type: 'continue' },
                        { from: TEST_EMAIL_ACTION_ID, to: EXIT_NODE_ID, type: 'continue' },
                    ]

                    const configuration: HogFlow = {
                        ...NEW_WORKFLOW,
                        team_id: currentTeamId ?? NEW_WORKFLOW.team_id,
                        name: template.name || 'Test email',
                        actions: [NEW_WORKFLOW.actions[0], emailAction, NEW_WORKFLOW.actions[1]],
                        edges,
                    }

                    return await api.hogFlows.createTestInvocation('new', {
                        configuration,
                        globals: createExampleEvent(
                            currentTeamId ?? undefined,
                            configuration.name,
                            '$pageview',
                            recipientEmail
                        ),
                        mock_async_functions: false,
                        current_action_id: TEST_EMAIL_ACTION_ID,
                    })
                },
            },
        ],
    })),
    selectors({
        emailIntegrations: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): IntegrationType[] =>
                integrations?.filter(
                    (integration) => integration.kind === 'email' && integration.config?.verified === true
                ) ?? [],
        ],
        senderIntegrationId: [
            (s) => [s.senderIntegrationIdOverride, s.emailIntegrations],
            (override: number | null, emailIntegrations: IntegrationType[]): number | null =>
                override ?? emailIntegrations[0]?.id ?? null,
        ],
        sendDisabledReason: [
            (s) => [s.template, s.recipientEmail, s.senderIntegrationId],
            (
                template: MessageTemplate,
                recipientEmail: string,
                senderIntegrationId: number | null
            ): string | undefined => {
                if (!template.content.email?.subject) {
                    return 'Add a subject first'
                }
                if (!template.content.email.text && !template.content.email.html) {
                    return 'Add email content first'
                }
                if (!recipientEmail || !isEmail(recipientEmail)) {
                    return 'Enter a valid email address'
                }
                if (!senderIntegrationId) {
                    return 'Connect an email sender first'
                }
                return undefined
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setModalOpen: ({ open }) => {
            if (!open) {
                return
            }
            actions.clearTestSendResult()
            if (!values.recipientEmail && values.user?.email) {
                actions.setRecipientEmail(values.user.email)
            }
        },
        sendTestEmailSuccess: ({ testSendResult }) => {
            if (testSendResult.status === 'success') {
                lemonToast.success(`Test email sent to ${values.recipientEmail}`)
                actions.setModalOpen(false)
                actions.clearTestSendResult()
            } else if (testSendResult.status === 'skipped') {
                lemonToast.warning('Test email skipped, see details below')
            } else {
                lemonToast.error('Failed to send test email')
            }
        },
        sendTestEmailFailure: () => {
            lemonToast.error('Failed to send test email')
        },
    })),
])
