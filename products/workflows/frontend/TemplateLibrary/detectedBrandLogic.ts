import { MakeLogicType, connect, kea, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { subscriptions } from 'kea-subscriptions'

import { ApiConfig } from 'lib/api'
import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'

import { messagingTemplatesDetectBrandCreate } from 'products/messaging/frontend/generated/api'
import type { DetectedBrandApi } from 'products/messaging/frontend/generated/api.schemas'

import type { FeatureFlagsSet } from '../../../../frontend/src/lib/logic/featureFlagLogic'

export type BrandDetectionOutcome = 'found' | 'partial' | 'none' | 'unavailable'

export function foundFieldsOutcome(
    brand: Pick<DetectedBrandApi, 'name' | 'primary_color' | 'logo_url'>
): Exclude<BrandDetectionOutcome, 'unavailable'> {
    const found = [brand.name, brand.primary_color, brand.logo_url].filter(Boolean)
    return found.length === 3 ? 'found' : found.length > 0 ? 'partial' : 'none'
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface detectedBrandLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    brandDetectionOutcome: BrandDetectionOutcome
    detectedBrand: DetectedBrandApi | null
    detectedBrandLoading: boolean
    brandedStarterEnabled: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface detectedBrandLogicActions {
    loadDetectedBrand: () => any
    loadDetectedBrandFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadDetectedBrandSuccess: (
        detectedBrand: DetectedBrandApi | null,
        payload?: any
    ) => {
        detectedBrand: DetectedBrandApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface detectedBrandLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        brandDetectionOutcome: (detectedBrand: any) => BrandDetectionOutcome
        brandedStarterEnabled: (featureFlags: FeatureFlagsSet) => boolean
    }
}

export type detectedBrandLogicType = MakeLogicType<
    detectedBrandLogicValues,
    detectedBrandLogicActions,
    Record<string, any>,
    detectedBrandLogicMeta
>

export const detectedBrandLogic = kea<detectedBrandLogicType>([
    path(['products', 'workflows', 'frontend', 'TemplateLibrary', 'detectedBrandLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),
    loaders(() => ({
        detectedBrand: [
            null as DetectedBrandApi | null,
            {
                loadDetectedBrand: async (): Promise<DetectedBrandApi | null> => {
                    try {
                        return await messagingTemplatesDetectBrandCreate(String(ApiConfig.getCurrentTeamId()))
                    } catch {
                        return null
                    }
                },
            },
        ],
    })),
    selectors({
        brandedStarterEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.EMAIL_BRANDED_STARTER],
        ],
        brandDetectionOutcome: [
            (s) => [s.detectedBrand],
            (detectedBrand: DetectedBrandApi | null): BrandDetectionOutcome =>
                detectedBrand ? foundFieldsOutcome(detectedBrand) : 'unavailable',
        ],
    }),
    subscriptions(({ actions }) => ({
        brandedStarterEnabled: (enabled: boolean) => {
            if (enabled) {
                actions.loadDetectedBrand()
            }
        },
    })),
])
