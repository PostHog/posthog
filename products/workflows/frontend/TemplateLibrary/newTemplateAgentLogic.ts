/** Entry, mode and picked starting point for the AI-first "New template" page. */
export const newTemplateAgentLogic = kea<newTemplateAgentLogicType>([
    path(['products', 'workflows', 'frontend', 'library', 'newTemplateAgentLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            sceneAgentPanelLogic,
            ['sceneIntegrationEnabled'],
            router,
            ['searchParams', 'location'],
        ],
        actions: [attachedContextLogic, ['dismissContext', 'undismissContext'], router, ['locationChanged']],
    })),
    actions({
        startNewTemplate: true,
        openEditorFromAiComposer: true,
        setPickedTemplate: (template: MessageTemplate | null) => ({ template }),
    }),
    reducers({
        pickedTemplate: [
            null as MessageTemplate | null,
            {
                setPickedTemplate: (_, { template }) => template,
            },
        ],
    }),
    selectors({
        // Same gate as the scene integration. Only the `test` variant, or a plain boolean rollout, qualifies.
        aiFirstNewEnabled: [
            (s) => [s.featureFlags, s.sceneIntegrationEnabled],
            (featureFlags: FeatureFlagsSet, sceneIntegrationEnabled: boolean): boolean =>
                sceneIntegrationEnabled && isAiFirstVariant(FEATURE_FLAGS.EMAIL_TEMPLATES_AI_FIRST_NEW, featureFlags),
        ],
        // A template started from a sent message has its starting point already, so it stays on the editor.
        aiComposerAvailable: [
            (s) => [s.featureFlags, s.sceneIntegrationEnabled, s.searchParams, s.location],
            (
                featureFlags: FeatureFlagsSet,
                sceneIntegrationEnabled: boolean,
                searchParams: Record<string, any>,
                location: { pathname: string }
            ): boolean =>
                aiComposerAvailable(
                    FEATURE_FLAGS.EMAIL_TEMPLATES_AI_FIRST_NEW,
                    featureFlags,
                    sceneIntegrationEnabled,
                    searchParams,
                    isNewTemplateRoute(location.pathname) && !searchParams.messageId
                ),
        ],
        agentContextItems: [
            (s) => [s.pickedTemplate],
            (pickedTemplate: MessageTemplate | null): AttachedContextItem[] =>
                buildNewTemplateComposerContext(pickedTemplate),
        ],
    }),
    listeners(({ actions, values }) => ({
        startNewTemplate: () => {
            // Exposure is recorded at the click, and only when the composer could answer it.
            if (values.sceneIntegrationEnabled) {
                posthog.getFeatureFlag(FEATURE_FLAGS.EMAIL_TEMPLATES_AI_FIRST_NEW)
            }
            router.actions.push(
                urls.workflowsLibraryTemplateNew(),
                values.aiFirstNewEnabled ? { [EDITOR_MODE_PARAM]: AI_COMPOSER_MODE_VALUE } : {}
            )
        },
        // The editor URL keeps the composer from rendering again, and the editor opens its picker for it.
        openEditorFromAiComposer: () => {
            router.actions.push(urls.workflowsLibraryTemplateNew(), { [EDITOR_MODE_PARAM]: EDITOR_MODE_VALUE })
        },
        setPickedTemplate: ({ template }) => {
            if (!template) {
                return
            }
            // A chip closed earlier in this session keeps its group dismissed, so a new pick lifts that first.
            actions.undismissContext(
                attachedContextItemKey(pickedTemplateContextItem(template)),
                PICKED_TEMPLATE_DISMISS_GROUP
            )
            posthog.capture('email template ai composer template picked', { template_id: template.id })
        },
        // Closing the chip is how the person un-picks; the context item is gone, so the state follows.
        dismissContext: ({ dismissGroup }) => {
            if (dismissGroup === PICKED_TEMPLATE_DISMISS_GROUP && values.pickedTemplate) {
                actions.setPickedTemplate(null)
            }
        },
        // The pick belongs to one visit of the page. The library keeps this logic mounted, so leaving has to clear it.
        locationChanged: ({ pathname }) => {
            if (values.pickedTemplate && !isNewTemplateRoute(pathname)) {
                actions.setPickedTemplate(null)
            }
        },
    })),
])
