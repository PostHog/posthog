export const brandedStarterLogic = kea<brandedStarterLogicType>([
    props({} as MessageTemplateLogicProps),
    path(['products', 'workflows', 'frontend', 'TemplateLibrary', 'brandedStarterLogic']),
    connect((props: MessageTemplateLogicProps) => ({
        values: [teamLogic, ['currentTeamIdStrict'], emailTemplaterLogic, ['emailEditorRef', 'isEmailEditorReady']],
        actions: [
            messageTemplateLogic(props),
            ['setTemplateValues', 'setBrandedStarterOpen'],
            emailTemplaterLogic,
            ['designLoaded'],
        ],
    })),
    forms(({ actions, values, cache }) => ({
        brand: {
            defaults: { name: '', primaryColor: '#1d4aff', logo: null } as BrandedStarterForm,
            errors: ({ name, primaryColor, logo }) => ({
                name: !name.trim().replace(/[{}]/g, '')
                    ? 'Enter a brand name'
                    : name.length > 255
                      ? 'Use 255 characters or fewer'
                      : undefined,
                primaryColor: !/^#[0-9a-f]{6}$/i.test(primaryColor)
                    ? 'Enter a six-digit hex color, like #1d4aff'
                    : undefined,
                logo:
                    logo &&
                    (!['image/png', 'image/jpeg', 'image/gif', 'image/webp'].includes(logo.type) ||
                        logo.size >= 4 * 1024 * 1024)
                        ? 'Choose a PNG, JPEG, GIF or WebP under 4 MB'
                        : undefined,
            }),
            submit: async ({ name, primaryColor, logo }) => {
                const editor = values.emailEditorRef?.editor
                if (!editor || !values.isEmailEditorReady) {
                    throw new Error('The email editor is loading. Try again in a moment.')
                }
                let logoUrl: string | undefined
                if (logo) {
                    const uploaded = await uploadedMediaCreate(String(values.currentTeamIdStrict), {
                        image: logo,
                        purpose: 'email',
                    })
                    if (typeof uploaded.image_location !== 'string') {
                        throw new Error('Could not upload the logo. Try again.')
                    }
                    logoUrl = uploaded.image_location
                }
                if (cache.disposables.isDisposed) {
                    return
                }
                const template = buildBrandedStarter({ name, primaryColor, logoUrl })
                const email = await new Promise<typeof template.content.email>((resolve, reject) => {
                    cache.disposables.add(
                        () => {
                            const timeout = setTimeout(() => {
                                cache.disposables.dispose('starterExport')
                                reject(new Error('Could not export the starter. Try again.'))
                            }, 30000)
                            cache.completeStarter = () => {
                                editor.exportHtml(
                                    ({
                                        html,
                                        design,
                                    }: {
                                        html: string
                                        design: NonNullable<typeof template.content.email.design>
                                    }) => {
                                        editor.exportPlainText(({ text }: { text: string }) => {
                                            cache.disposables.dispose('starterExport')
                                            resolve({ ...template.content.email, html, text, design })
                                        })
                                    }
                                )
                            }
                            return () => {
                                clearTimeout(timeout)
                                cache.completeStarter = null
                            }
                        },
                        'starterExport',
                        { pauseOnPageHidden: false }
                    )
                    editor.loadDesign(template.content.email.design!)
                })
                if (!cache.disposables.isDisposed) {
                    actions.setTemplateValues({ ...template, content: { ...template.content, email } })
                }
            },
        },
    })),
    listeners(({ actions, cache }) => ({
        designLoaded: () => {
            cache.completeStarter?.()
        },
        submitBrandSuccess: () => {
            actions.setBrandedStarterOpen(false)
        },
        submitBrandFailure: ({ error }) => {
            lemonToast.error(error.message || 'Could not generate the starter. Try again.')
        },
    })),
])
