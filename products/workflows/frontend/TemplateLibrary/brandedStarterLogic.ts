export const brandedStarterLogic = kea<brandedStarterLogicType>([
    props({} as MessageTemplateLogicProps),
    path(['products', 'workflows', 'frontend', 'TemplateLibrary', 'brandedStarterLogic']),
    connect((props: MessageTemplateLogicProps) => ({
        values: [
            teamLogic,
            ['currentTeamIdStrict'],
            emailTemplaterLogic,
            ['emailEditorRef', 'isEmailEditorReady'],
            detectedBrandLogic,
            ['detectedBrand', 'detectedBrandLoading', 'brandDetectionOutcome', 'brandedStarterEnabled'],
            savedBrandLogic,
            ['savedBrand', 'isSavedBrandKnown', 'savedBrandLoading', 'savedBrandLoadError'],
        ],
        actions: [
            messageTemplateLogic(props),
            ['setTemplateValues', 'setBrandedStarterOpen'],
            emailTemplaterLogic,
            ['designLoaded'],
            detectedBrandLogic,
            ['loadDetectedBrandSuccess'],
            savedBrandLogic,
            ['loadSavedBrandSuccess', 'brandSaved'],
        ],
    })),
    actions({
        applyBrandPrefill: true,
        brandPrefilled: (prefilledFrom: BrandPrefill, fields: BrandField[], host: string | null = null) => ({
            prefilledFrom,
            fields,
            host,
        }),
        detectBrandFromGitHub: (integrationId: number, repository: string) => ({ integrationId, repository }),
        detectBrandFromGitHubSuccess: (detected: GitHubBrandApi) => ({ detected }),
        detectBrandFromGitHubFailure: (error: string) => ({ error }),
    }),
    reducers({
        prefilledFrom: [
            null as BrandPrefill | null,
            {
                brandPrefilled: (_, { prefilledFrom }) => prefilledFrom,
            },
        ],
        prefilledFromHost: [
            null as string | null,
            {
                brandPrefilled: (_, { host }) => host,
            },
        ],
        prefilledFields: [
            [] as BrandField[],
            {
                brandPrefilled: (_, { fields }) => fields,
            },
        ],
        isDetectingFromGitHub: [
            false,
            {
                detectBrandFromGitHub: () => true,
                detectBrandFromGitHubSuccess: () => false,
                detectBrandFromGitHubFailure: () => false,
            },
        ],
        hostedLogoFrom: [
            null as BrandPrefill | null,
            {
                brandPrefilled: (state, { prefilledFrom, fields }) => (fields.includes('logo') ? prefilledFrom : state),
            },
        ],
        githubDetectionError: [
            null as string | null,
            {
                detectBrandFromGitHub: () => null,
                detectBrandFromGitHubFailure: (_, { error }) => error,
            },
        ],
        editedBrandFields: [
            {} as Partial<Record<BrandField, true>>,
            {
                setBrandValue: (state, { name }) => ({ ...state, [String(name)]: true }),
                resetBrand: () => ({}),
            },
        ],
    }),
    selectors({
        savedBrandBlockReason: [
            (s) => [s.isSavedBrandKnown, s.savedBrandLoading, s.savedBrandLoadError, s.brandedStarterEnabled],
            (
                isSavedBrandKnown: boolean,
                savedBrandLoading: boolean,
                savedBrandLoadError: SavedBrandLoadError | null,
                brandedStarterEnabled: boolean
            ): string | null =>
                savedBrandLoadError
                    ? 'Could not load your saved brand'
                    : savedBrandLoading || (brandedStarterEnabled && !isSavedBrandKnown)
                      ? 'Loading your saved brand'
                      : null,
        ],
        brandSource: [
            (s) => [s.prefilledFrom, s.savedBrand],
            (prefilledFrom: BrandPrefill | null, savedBrand: SavedBrand): EmailBrandSourceEnumApi =>
                prefilledFrom === 'saved' ? (savedBrand?.source ?? 'manual') : (prefilledFrom ?? 'manual'),
        ],
        generateBlockReason: [
            (s) => [s.savedBrandBlockReason, s.isDetectingFromGitHub],
            (savedBrandBlockReason: string | null, isDetectingFromGitHub: boolean): string | null =>
                savedBrandBlockReason ?? (isDetectingFromGitHub ? 'Reading your GitHub repository' : null),
        ],
    }),
    forms(({ actions, values, cache }) => {
        const uploadLogo = async (logo: File, teamId: number | string): Promise<string> => {
            const previousUpload: UploadedLogo | undefined = cache.uploadedLogo
            if (previousUpload?.file === logo && previousUpload.teamId === teamId) {
                return previousUpload.url
            }
            const controller = new AbortController()
            cache.disposables.add(
                () => {
                    const timeout = setTimeout(() => controller.abort(), LOGO_UPLOAD_TIMEOUT_MS)
                    return () => {
                        clearTimeout(timeout)
                        controller.abort()
                    }
                },
                'starterUpload',
                { pauseOnPageHidden: false }
            )
            try {
                const uploaded = await uploadedMediaCreate(
                    String(teamId),
                    { image: logo, purpose: 'email' },
                    { signal: controller.signal }
                )
                if (typeof uploaded.image_location !== 'string') {
                    throw new Error('Could not upload the logo. Try again.')
                }
                cache.uploadedLogo = { file: logo, teamId, url: uploaded.image_location }
                return uploaded.image_location
            } catch (error) {
                throw controller.signal.aborted ? new Error('Logo upload timed out. Try again.') : error
            } finally {
                cache.disposables.dispose('starterUpload')
            }
        }

        const saveBrand = async (
            brand: Required<Omit<EmailBrandApi, 'id' | 'created_at' | 'updated_at'>>
        ): Promise<EmailBrandApi> => {
            try {
                return await emailBrandCurrentPartialUpdate(String(values.currentTeamIdStrict), brand)
            } catch (error) {
                throw new Error(saveFailureMessage(error))
            }
        }

        const exportStarter = (editor: Editor, starter: EmailTemplate): Promise<EmailTemplate> =>
            new Promise((resolve, reject) => {
                cache.disposables.add(
                    () => {
                        let active = true
                        const timeout = setTimeout(() => {
                            reject(new Error('Could not generate the starter. Try again.'))
                            cache.disposables.dispose('starterExport')
                        }, STARTER_EXPORT_TIMEOUT_MS)
                        cache.completeStarter = async () => {
                            const [{ html, design }, { text }] = await Promise.all([
                                exportEditorHtml(editor),
                                new Promise<{ text: string }>((done) => editor.exportPlainText(done)),
                            ])
                            if (active) {
                                resolve({ ...starter, html, text, design })
                                cache.disposables.dispose('starterExport')
                            }
                        }
                        return () => {
                            active = false
                            clearTimeout(timeout)
                            cache.completeStarter = null
                            reject(new Error('Starter export cancelled'))
                        }
                    },
                    'starterExport',
                    { pauseOnPageHidden: false }
                )
                editor.loadDesign(starter.design!)
            })

        return {
            brand: {
                defaults: DEFAULT_BRAND,
                errors: ({ name, primaryColor, logo }) => ({
                    name: !brandDisplayName(name) ? 'Enter a brand name' : undefined,
                    primaryColor: !/^#[0-9a-f]{6}$/i.test(primaryColor)
                        ? 'Enter a six-digit hex color, like #1d4aff'
                        : undefined,
                    logo:
                        logo instanceof File &&
                        (!['image/png', 'image/jpeg', 'image/gif', 'image/webp'].includes(logo.type) ||
                            logo.size >= 4 * 1024 * 1024)
                            ? 'Choose a PNG, JPEG, GIF or WebP under 4 MB'
                            : undefined,
                }),
                submit: async ({ name, primaryColor, logo }, breakpoint) => {
                    const editor = values.emailEditorRef?.editor
                    if (!editor || !values.isEmailEditorReady) {
                        throw new Error('The email editor is loading. Try again in a moment.')
                    }
                    if (values.generateBlockReason) {
                        throw new Error(values.generateBlockReason)
                    }
                    const logoUrl =
                        logo instanceof File
                            ? await uploadLogo(logo, values.currentTeamIdStrict).finally(() => breakpoint())
                            : logo || undefined
                    const savedBrand = await saveBrand({
                        name,
                        primary_color: primaryColor,
                        logo_url: logoUrl ?? null,
                        source: values.brandSource,
                    }).finally(() => breakpoint())
                    actions.brandSaved(savedBrand)
                    const template = buildBrandedStarter({ name, primaryColor, logoUrl })
                    const email = await exportStarter(editor, template.content.email).finally(() => breakpoint())
                    actions.setTemplateValues({ ...template, content: { ...template.content, email } })
                },
            },
        }
    }),
    listeners(({ actions, values, cache }) => ({
        designLoaded: () => {
            cache.completeStarter?.()
        },
        loadDetectedBrandSuccess: () => {
            actions.applyBrandPrefill()
        },
        loadSavedBrandSuccess: () => {
            actions.applyBrandPrefill()
        },
        applyBrandPrefill: () => {
            const { savedBrand, detectedBrand } = values
            if (
                values.isBrandSubmitting ||
                !values.isSavedBrandKnown ||
                values.savedBrandBlockReason ||
                (values.prefilledFrom !== null && values.prefilledFrom !== 'website')
            ) {
                return
            }
            const applyFill = (fill: Partial<BrandedStarterForm>): void => {
                if (values.brandChanged) {
                    actions.setBrandValues(fill)
                } else {
                    actions.resetBrand({ ...values.brand, ...fill })
                }
            }
            if (savedBrand) {
                const fill = brandFill(savedBrand, values.editedBrandFields)
                applyFill(fill)
                actions.brandPrefilled('saved', Object.keys(fill) as BrandField[])
                return
            }
            if (!detectedBrand?.website) {
                return
            }
            const fill = brandFill(detectedBrand, values.editedBrandFields)
            const fields = Object.keys(fill) as BrandField[]
            if (fields.length === 0) {
                return
            }
            applyFill(fill)
            actions.brandPrefilled('website', fields, new URL(detectedBrand.website).hostname)
        },
        detectBrandFromGitHub: async ({ integrationId, repository }, breakpoint) => {
            let detected: GitHubBrandApi
            try {
                detected = await emailBrandDetectFromGithubCreate(String(values.currentTeamIdStrict), {
                    integration_id: integrationId,
                    repository,
                })
            } catch (error) {
                breakpoint()
                actions.detectBrandFromGitHubFailure(githubDetectionFailureMessage(error))
                return
            }
            breakpoint()
            actions.detectBrandFromGitHubSuccess(detected)
        },
        detectBrandFromGitHubSuccess: ({ detected }) => {
            const fill = brandFill(detected, {})
            actions.setBrandValues(fill)
            actions.brandPrefilled('github', Object.keys(fill) as BrandField[], detected.repository)
            posthog.capture('email brand github detection', { outcome: foundFieldsOutcome(detected) })
        },
        detectBrandFromGitHubFailure: () => {
            posthog.capture('email brand github detection', { outcome: 'failed' })
        },
        submitBrandSuccess: ({ brand }) => {
            posthog.capture('email branded starter generated', starterProperties({ ...values, brand }))
            actions.setBrandedStarterOpen(false)
        },
        submitBrandFailure: ({ error }) => {
            if (!values.brandHasErrors) {
                const reason = error.message || 'Could not generate the starter. Try again.'
                posthog.capture('email branded starter failed', { ...starterProperties(values), reason })
                lemonToast.error(reason)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.applyBrandPrefill()
    }),
])

interface StarterProperties {
    has_logo: boolean
    logo_source: ReturnType<typeof logoSource>
    brand_detection: BrandDetectionOutcome
    prefilled_from: BrandPrefill | 'none'
    prefilled: boolean
    edited_prefill: boolean
}

function starterProperties({
    brand,
    brandDetectionOutcome,
    prefilledFrom,
    hostedLogoFrom,
    prefilledFields,
    editedBrandFields,
}: brandedStarterLogicValues): StarterProperties {
    return {
        has_logo: !!brand.logo,
        logo_source: logoSource(brand.logo, hostedLogoFrom),
        brand_detection: brandDetectionOutcome,
        prefilled_from: prefilledFrom ?? 'none',
        prefilled: prefilledFields.length > 0,
        edited_prefill: prefilledFields.some((field) => editedBrandFields[field]),
    }
}

function saveFailureMessage(error: unknown): string {
    const isClientError = error instanceof ApiError && !!error.status && error.status < 500
    return isClientError && error.detail ? error.detail : 'Could not save your brand. Try again.'
}

function githubDetectionFailureMessage(error: unknown): string {
    const isClientError = error instanceof ApiError && !!error.status && error.status < 500
    return isClientError && error.detail ? error.detail : 'Could not read your GitHub repository. Try again.'
}
