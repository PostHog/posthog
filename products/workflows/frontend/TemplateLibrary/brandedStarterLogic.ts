export const brandedStarterLogic = kea<brandedStarterLogicType>([
    props({} as MessageTemplateLogicProps),
    path(['products', 'workflows', 'frontend', 'TemplateLibrary', 'brandedStarterLogic']),
    connect((props: MessageTemplateLogicProps) => ({
        values: [
            teamLogic,
            ['currentTeamIdStrict'],
            emailTemplaterLogic,
            ['emailEditorRef', 'isEmailEditorReady'],
            detectedBrandLogic,
            ['detectedBrand', 'detectedBrandLoading', 'brandDetectionOutcome'],
        ],
        actions: [
            messageTemplateLogic(props),
            ['setTemplateValues', 'setBrandedStarterOpen'],
            emailTemplaterLogic,
            ['designLoaded'],
            detectedBrandLogic,
            ['loadDetectedBrandSuccess'],
        ],
    })),
    actions({
        applyDetectedBrand: (detectedBrand: DetectedBrandApi | null) => ({ detectedBrand }),
        brandPrefilled: (host: string, fields: BrandField[]) => ({ host, fields }),
    }),
    reducers({
        prefilledFromHost: [
            null as string | null,
            {
                brandPrefilled: (_, { host }) => host,
            },
        ],
        prefilledFields: [
            [] as BrandField[],
            {
                brandPrefilled: (_, { fields }) => fields,
            },
        ],
        editedBrandFields: [
            {} as Partial<Record<BrandField, true>>,
            {
                setBrandValue: (state, { name }) => ({ ...state, [String(name)]: true }),
                resetBrand: () => ({}),
            },
        ],
    }),
    forms(({ actions, values, cache }) => {
        const uploadLogo = async (logo: File, teamId: number | string): Promise<string> => {
            const previousUpload: UploadedLogo | undefined = cache.uploadedLogo
            if (previousUpload?.file === logo && previousUpload.teamId === teamId) {
                return previousUpload.url
            }
            const controller = new AbortController()
            cache.disposables.add(
                () => {
                    const timeout = setTimeout(() => controller.abort(), LOGO_UPLOAD_TIMEOUT_MS)
                    return () => {
                        clearTimeout(timeout)
                        controller.abort()
                    }
                },
                'starterUpload',
                { pauseOnPageHidden: false }
            )
            try {
                const uploaded = await uploadedMediaCreate(
                    String(teamId),
                    { image: logo, purpose: 'email' },
                    { signal: controller.signal }
                )
                if (typeof uploaded.image_location !== 'string') {
                    throw new Error('Could not upload the logo. Try again.')
                }
                cache.uploadedLogo = { file: logo, teamId, url: uploaded.image_location }
                return uploaded.image_location
            } catch (error) {
                throw controller.signal.aborted ? new Error('Logo upload timed out. Try again.') : error
            } finally {
                cache.disposables.dispose('starterUpload')
            }
        }

        const exportStarter = (editor: Editor, starter: EmailTemplate): Promise<EmailTemplate> =>
            new Promise((resolve, reject) => {
                cache.disposables.add(
                    () => {
                        let active = true
                        const timeout = setTimeout(() => {
                            reject(new Error('Could not generate the starter. Try again.'))
                            cache.disposables.dispose('starterExport')
                        }, STARTER_EXPORT_TIMEOUT_MS)
                        cache.completeStarter = async () => {
                            const [{ html, design }, { text }] = await Promise.all([
                                exportEditorHtml(editor),
                                new Promise<{ text: string }>((done) => editor.exportPlainText(done)),
                            ])
                            if (active) {
                                resolve({ ...starter, html, text, design })
                                cache.disposables.dispose('starterExport')
                            }
                        }
                        return () => {
                            active = false
                            clearTimeout(timeout)
                            cache.completeStarter = null
                            reject(new Error('Starter export cancelled'))
                        }
                    },
                    'starterExport',
                    { pauseOnPageHidden: false }
                )
                editor.loadDesign(starter.design!)
            })

        return {
            brand: {
                defaults: DEFAULT_BRAND,
                errors: ({ name, primaryColor, logo }) => ({
                    name: !brandDisplayName(name) ? 'Enter a brand name' : undefined,
                    primaryColor: !/^#[0-9a-f]{6}$/i.test(primaryColor)
                        ? 'Enter a six-digit hex color, like #1d4aff'
                        : undefined,
                    logo:
                        logo instanceof File &&
                        (!['image/png', 'image/jpeg', 'image/gif', 'image/webp'].includes(logo.type) ||
                            logo.size >= 4 * 1024 * 1024)
                            ? 'Choose a PNG, JPEG, GIF or WebP under 4 MB'
                            : undefined,
                }),
                submit: async ({ name, primaryColor, logo }, breakpoint) => {
                    const editor = values.emailEditorRef?.editor
                    if (!editor || !values.isEmailEditorReady) {
                        throw new Error('The email editor is loading. Try again in a moment.')
                    }
                    const logoUrl =
                        logo instanceof File
                            ? await uploadLogo(logo, values.currentTeamIdStrict).finally(() => breakpoint())
                            : logo || undefined
                    const template = buildBrandedStarter({ name, primaryColor, logoUrl })
                    const email = await exportStarter(editor, template.content.email).finally(() => breakpoint())
                    actions.setTemplateValues({ ...template, content: { ...template.content, email } })
                },
            },
        }
    }),
    listeners(({ actions, values, cache }) => ({
        designLoaded: () => {
            cache.completeStarter?.()
        },
        loadDetectedBrandSuccess: ({ detectedBrand }) => {
            actions.applyDetectedBrand(detectedBrand)
        },
        applyDetectedBrand: ({ detectedBrand }) => {
            if (!detectedBrand?.website || values.isBrandSubmitting) {
                return
            }
            const fill = detectedFill(detectedBrand, values.editedBrandFields)
            const fields = Object.keys(fill) as BrandField[]
            if (fields.length === 0) {
                return
            }
            if (values.brandChanged) {
                actions.setBrandValues(fill)
            } else {
                actions.resetBrand({ ...values.brand, ...fill })
            }
            actions.brandPrefilled(new URL(detectedBrand.website).hostname, fields)
        },
        submitBrandSuccess: ({ brand }) => {
            posthog.capture('email branded starter generated', starterProperties({ ...values, brand }))
            actions.setBrandedStarterOpen(false)
        },
        submitBrandFailure: ({ error }) => {
            if (!values.brandHasErrors) {
                const reason = error.message || 'Could not generate the starter. Try again.'
                posthog.capture('email branded starter failed', { ...starterProperties(values), reason })
                lemonToast.error(reason)
            }
        },
    })),
    afterMount(({ actions, values }) => {
        actions.applyDetectedBrand(values.detectedBrand)
    }),
])

interface StarterProperties {
    has_logo: boolean
    logo_source: ReturnType<typeof logoSource>
    brand_detection: BrandDetectionOutcome
    prefilled: boolean
    edited_prefill: boolean
}

function starterProperties({
    brand,
    brandDetectionOutcome,
    prefilledFields,
    editedBrandFields,
}: brandedStarterLogicValues): StarterProperties {
    return {
        has_logo: !!brand.logo,
        logo_source: logoSource(brand.logo),
        brand_detection: brandDetectionOutcome,
        prefilled: prefilledFields.length > 0,
        edited_prefill: prefilledFields.some((field) => editedBrandFields[field]),
    }
}
