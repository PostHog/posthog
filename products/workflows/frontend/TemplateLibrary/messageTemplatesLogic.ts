export type messageTemplatesLogicType = MakeLogicType<
    messageTemplatesLogicValues,
    messageTemplatesLogicActions,
    Record<string, any>,
    messageTemplatesLogicMeta
>

export const messageTemplatesLogic = kea<messageTemplatesLogicType>([
    path(['products', 'workflows', 'frontend', 'library', 'messageTemplatesLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], tagsModel, ['tags']],
        actions: [tagsModel, ['loadTags', 'loadTagsIfNeeded']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setCreatedByFilter: (createdBy: number | null) => ({ createdBy }),
        setTransactionalOnly: (transactionalOnly: boolean) => ({ transactionalOnly }),
        setTagsFilter: (tagsFilter: string[]) => ({ tagsFilter }),
        templateTagsSaved: (template: MessageTemplate) => ({ template }),
    }),
    reducers({
        search: ['' as string, { setSearch: (_, { search }) => search }],
        createdByFilter: [null as number | null, { setCreatedByFilter: (_, { createdBy }) => createdBy }],
        transactionalOnly: [false, { setTransactionalOnly: (_, { transactionalOnly }) => transactionalOnly }],
        tagsFilter: [[] as string[], { setTagsFilter: (_, { tagsFilter }) => tagsFilter }],
        templates: [
            [] as MessageTemplateListItem[],
            {
                templateTagsSaved: (state, { template }) =>
                    state.map((t: MessageTemplateListItem) => (t.id === template.id ? template : t)),
            },
        ],
    }),
    loaders(({ values, actions }) => ({
        templates: [
            [] as MessageTemplateListItem[],
            {
                loadTemplates: async () => {
                    const response = await messagingTemplatesList(String(values.currentTeamIdStrict), {
                        include_design: false,
                    })
                    return response.results
                },
                deleteTemplate: async (template: MessageTemplateListItem) => {
                    await deleteWithUndo({
                        endpoint: `environments/${values.currentTeamIdStrict}/messaging_templates`,
                        object: {
                            id: template.id,
                            name: template.name,
                        },
                        callback: (undo) => {
                            if (undo) {
                                actions.loadTemplates()
                            }
                        },
                    })
                    return values.templates.filter((t: MessageTemplateListItem) => t.id !== template.id)
                },
                createTemplate: async ({ template }: { template: Partial<MessageTemplate> }) => {
                    try {
                        const newTemplate = await api.messaging.createTemplate(template)
                        lemonToast.success('Template created successfully')
                        return [...values.templates, newTemplate]
                    } catch {
                        lemonToast.error('Failed to create template')
                        return values.templates
                    }
                },
                updateTemplate: async ({
                    templateId,
                    template,
                }: {
                    templateId: string
                    template: Partial<MessageTemplate>
                }) => {
                    try {
                        const updatedTemplate = await api.messaging.updateTemplate(templateId, template)
                        lemonToast.success('Template updated successfully')
                        return values.templates.map((t: MessageTemplateListItem) =>
                            t.id === templateId ? updatedTemplate : t
                        )
                    } catch {
                        lemonToast.error('Failed to update template')
                        return values.templates
                    }
                },
                duplicateTemplate: async (template: MessageTemplateListItem) => {
                    try {
                        const fullTemplate = await messagingTemplatesRetrieve(
                            String(values.currentTeamIdStrict),
                            template.id
                        )
                        const duplicatedTemplate = await messagingTemplatesCreate(String(values.currentTeamIdStrict), {
                            name: `${fullTemplate.name} (copy)`,
                            description: fullTemplate.description,
                            content: fullTemplate.content,
                        })
                        lemonToast.success('Template duplicated successfully')
                        return [...values.templates, duplicatedTemplate]
                    } catch {
                        lemonToast.error('Failed to duplicate template')
                        return values.templates
                    }
                },
            },
        ],
    })),
    selectors({
        transactionalTemplates: [
            (s) => [s.templates],
            (templates: MessageTemplateListItem[]): MessageTemplateListItem[] =>
                templates.filter((t) => !!t.transactional_hog_flow_id),
        ],
        filteredTemplates: [
            (s) => [s.templates, s.search, s.createdByFilter, s.transactionalOnly, s.tagsFilter],
            (
                templates: MessageTemplateListItem[],
                search: string,
                createdByFilter: number | null,
                transactionalOnly: boolean,
                tagsFilter: string[]
            ): MessageTemplateListItem[] =>
                filterMessageTemplates(templates, {
                    search,
                    tags: tagsFilter,
                    createdBy: createdByFilter,
                    transactionalOnly,
                }),
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadTemplates()
        actions.loadTagsIfNeeded()
    }),
])

// A plain function rather than a listener, because the caller awaits it to keep its editor open on
// a rejection, and a kea listener that rethrows raises an unhandled rejection on the way out.
export async function saveTemplateTags(template: MessageTemplate, tags: string[]): Promise<void> {
    const updated = await api.messaging.updateTemplate(template.id, { tags })
    messageTemplatesLogic.findMounted()?.actions.templateTagsSaved(updated)
    tagsModel.findMounted()?.actions.loadTags()
}
