export const messageTemplatesLogic = kea<messageTemplatesLogicType>([
    path(['products', 'workflows', 'frontend', 'library', 'messageTemplatesLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamIdStrict'],
            workflowTemplatesLogic,
            ['workflowTemplates', 'workflowTemplatesLoading'],
        ],
        actions: [workflowTemplatesLogic, ['deleteHogflowTemplate']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setCreatedByFilter: (createdBy: number | null) => ({ createdBy }),
        setTypeFilter: (typeFilter: LibraryTypeFilter) => ({ typeFilter }),
        clearFilters: true,
    }),
    reducers({
        search: ['' as string, { setSearch: (_, { search }) => search, clearFilters: () => '' }],
        createdByFilter: [
            null as number | null,
            { setCreatedByFilter: (_, { createdBy }) => createdBy, clearFilters: () => null },
        ],
        typeFilter: [
            'all' as LibraryTypeFilter,
            { setTypeFilter: (_, { typeFilter }) => typeFilter, clearFilters: () => 'all' as const },
        ],
    }),
    loaders(({ values, actions }) => ({
        templates: [
            [] as MessageTemplate[],
            {
                loadTemplates: async () => {
                    const response = await api.messaging.getTemplates()
                    return response.results
                },
                deleteTemplate: async (template: MessageTemplate) => {
                    await deleteWithUndo({
                        endpoint: `environments/${values.currentTeamIdStrict}/messaging_templates`,
                        object: {
                            id: template.id,
                            name: template.name,
                        },
                        callback: (undo) => {
                            if (undo) {
                                actions.loadTemplates()
                            }
                        },
                    })
                    return values.templates.filter((t: MessageTemplate) => t.id !== template.id)
                },
                createTemplate: async ({ template }: { template: Partial<MessageTemplate> }) => {
                    try {
                        const newTemplate = await api.messaging.createTemplate(template)
                        lemonToast.success('Template created successfully')
                        return [...values.templates, newTemplate]
                    } catch {
                        lemonToast.error('Failed to create template')
                        return values.templates
                    }
                },
                updateTemplate: async ({
                    templateId,
                    template,
                }: {
                    templateId: string
                    template: Partial<MessageTemplate>
                }) => {
                    try {
                        const updatedTemplate = await api.messaging.updateTemplate(templateId, template)
                        lemonToast.success('Template updated successfully')
                        return values.templates.map((t: MessageTemplate) => (t.id === templateId ? updatedTemplate : t))
                    } catch {
                        lemonToast.error('Failed to update template')
                        return values.templates
                    }
                },
                duplicateTemplate: async (template: MessageTemplate) => {
                    try {
                        const duplicatedTemplate = await api.messaging.createTemplate({
                            name: `${template.name} (copy)`,
                            description: template.description,
                            type: template.type,
                            content: template.content,
                        })
                        lemonToast.success('Template duplicated successfully')
                        return [...values.templates, duplicatedTemplate]
                    } catch {
                        lemonToast.error('Failed to duplicate template')
                        return values.templates
                    }
                },
            },
        ],
    })),
    selectors({
        filteredTemplates: [
            (s) => [s.templates, s.search, s.createdByFilter, s.typeFilter],
            (
                templates: MessageTemplate[],
                search: string,
                createdByFilter: number | null,
                typeFilter: LibraryTypeFilter
            ): MessageTemplate[] => {
                let filtered = templates
                if (search) {
                    filtered = filtered.filter((t) => matchesSearch(t, search))
                }
                if (createdByFilter !== null) {
                    filtered = filtered.filter((t) => t.created_by?.id === createdByFilter)
                }
                if (typeFilter !== 'all') {
                    filtered = filtered.filter((t) => (t.type ?? 'email') === typeFilter)
                }
                return filtered
            },
        ],
        savedWorkflowTemplates: [
            (s) => [s.workflowTemplates],
            // Built-in templates ship with PostHog and are offered when you create a workflow.
            // The library only holds what this project saved.
            (workflowTemplates: HogFlowTemplate[]): HogFlowTemplate[] =>
                workflowTemplates.filter((t) => t.scope !== 'global'),
        ],
        filteredWorkflowTemplates: [
            (s) => [s.savedWorkflowTemplates, s.search, s.createdByFilter, s.typeFilter],
            (
                workflowTemplates: HogFlowTemplate[],
                search: string,
                createdByFilter: number | null,
                typeFilter: LibraryTypeFilter
            ): HogFlowTemplate[] => {
                if (typeFilter !== 'all' && typeFilter !== 'workflow') {
                    return []
                }
                let filtered = workflowTemplates
                if (search) {
                    filtered = filtered.filter((t) => matchesSearch(t, search))
                }
                if (createdByFilter !== null) {
                    filtered = filtered.filter((t) => t.created_by?.id === createdByFilter)
                }
                return filtered
            },
        ],
        libraryItems: [
            (s) => [s.filteredTemplates, s.filteredWorkflowTemplates],
            // Newest first across both kinds, so a template you just saved is at the front of the
            // grid rather than below every email.
            (templates: MessageTemplate[], workflowTemplates: HogFlowTemplate[]): LibraryItem[] =>
                [
                    ...templates.map(
                        (template): LibraryItem => ({
                            kind: 'message',
                            createdAt: template.created_at ?? '',
                            template,
                        })
                    ),
                    ...workflowTemplates.map(
                        (template): LibraryItem => ({
                            kind: 'workflow',
                            createdAt: template.created_at ?? '',
                            template,
                        })
                    ),
                ].sort((a, b) => b.createdAt.localeCompare(a.createdAt)),
        ],
        libraryLoading: [
            (s) => [s.templatesLoading, s.workflowTemplatesLoading],
            (templatesLoading: boolean, workflowTemplatesLoading: boolean): boolean =>
                templatesLoading || workflowTemplatesLoading,
        ],
        isLibraryEmpty: [
            (s) => [s.libraryLoading, s.templates, s.savedWorkflowTemplates],
            (
                libraryLoading: boolean,
                templates: MessageTemplate[],
                savedWorkflowTemplates: HogFlowTemplate[]
            ): boolean => !libraryLoading && templates.length === 0 && savedWorkflowTemplates.length === 0,
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadTemplates()
    }),
])
