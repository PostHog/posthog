export type { MessageTemplate }

export type LibraryTypeFilter = 'all' | MessageTemplate['type'] | 'workflow'

export type LibraryItem =
    | { kind: 'message'; createdAt: string; template: MessageTemplate }
    | { kind: 'workflow'; createdAt: string; template: HogFlowTemplate }

const matchesSearch = (item: { name?: string | null; description?: string | null }, search: string): boolean => {
    const lowerSearch = search.toLowerCase()
    return (
        (item.name ?? '').toLowerCase().includes(lowerSearch) ||
        (item.description ?? '').toLowerCase().includes(lowerSearch)
    )
}

