import { MakeLogicType, actions, beforeUnmount, connect, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { subscriptions } from 'kea-subscriptions'

import { ApiConfig } from 'lib/api'
import { ApiError } from 'lib/api-error'
import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'

import { emailBrandCurrentRetrieve } from 'products/messaging/frontend/generated/api'
import type { EmailBrandApi } from 'products/messaging/frontend/generated/api.schemas'

import type { FeatureFlagsSet } from '../../../../frontend/src/lib/logic/featureFlagLogic'

export type SavedBrand = EmailBrandApi | null

export interface SavedBrandLoadError {
    message: string
    retryable: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface savedBrandLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    brandedStarterEnabled: boolean
    isSavedBrandKnown: boolean
    savedBrand: SavedBrand
    savedBrandLoadError: SavedBrandLoadError | null
    savedBrandLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface savedBrandLogicActions {
    brandSaved: (savedBrand: EmailBrandApi) => {
        savedBrand: EmailBrandApi
    }
    forgetSavedBrand: () => {
        value: true
    }
    loadSavedBrand: (_?: any) => any
    loadSavedBrandFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSavedBrandSuccess: (
        savedBrand: SavedBrand,
        payload?: any
    ) => {
        savedBrand: SavedBrand
        payload?: any
    }
    markSavedBrandAnswered: () => {
        value: true
    }
    markSavedBrandUnavailable: (loadError: SavedBrandLoadError) => {
        loadError: SavedBrandLoadError
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface savedBrandLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        brandedStarterEnabled: (featureFlags: FeatureFlagsSet) => boolean
    }
}

export type savedBrandLogicType = MakeLogicType<
    savedBrandLogicValues,
    savedBrandLogicActions,
    Record<string, any>,
    savedBrandLogicMeta
>

export const savedBrandLogic = kea<savedBrandLogicType>([
    path(['products', 'workflows', 'frontend', 'TemplateLibrary', 'savedBrandLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),
    actions({
        brandSaved: (savedBrand: EmailBrandApi) => ({ savedBrand }),
        markSavedBrandUnavailable: (loadError: SavedBrandLoadError) => ({ loadError }),
        markSavedBrandAnswered: true,
        forgetSavedBrand: true,
    }),
    loaders(({ actions, values }) => ({
        savedBrand: [
            null as SavedBrand,
            {
                loadSavedBrand: async (_, breakpoint): Promise<SavedBrand> => {
                    let savedBrand: SavedBrand
                    try {
                        savedBrand = await emailBrandCurrentRetrieve(String(ApiConfig.getCurrentTeamId()))
                    } catch (error) {
                        breakpoint()
                        if (!isNoSavedBrand(error)) {
                            actions.markSavedBrandUnavailable(loadErrorFrom(error))
                            return values.savedBrand
                        }
                        savedBrand = null
                    }
                    breakpoint()
                    actions.markSavedBrandAnswered()
                    return savedBrand
                },
            },
        ],
    })),
    reducers({
        savedBrand: {
            brandSaved: (_, { savedBrand }) => savedBrand,
            forgetSavedBrand: () => null,
        },
        isSavedBrandKnown: [
            false,
            {
                markSavedBrandAnswered: () => true,
                brandSaved: () => true,
                forgetSavedBrand: () => false,
            },
        ],
        savedBrandLoadError: [
            null as SavedBrandLoadError | null,
            {
                markSavedBrandUnavailable: (_, { loadError }) => loadError,
                markSavedBrandAnswered: () => null,
                forgetSavedBrand: () => null,
            },
        ],
    }),
    selectors({
        brandedStarterEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.EMAIL_BRANDED_STARTER],
        ],
    }),
    subscriptions(({ actions }) => ({
        brandedStarterEnabled: (enabled: boolean) => {
            if (enabled) {
                actions.loadSavedBrand()
            }
        },
    })),
    beforeUnmount(({ actions }) => {
        actions.forgetSavedBrand()
    }),
])

function isNoSavedBrand(error: unknown): boolean {
    return error instanceof ApiError && error.status === 404
}

function loadErrorFrom(error: unknown): SavedBrandLoadError {
    const isClientError = error instanceof ApiError && !!error.status && error.status < 500
    return isClientError && error.detail
        ? { message: error.detail, retryable: false }
        : { message: 'Could not load your saved brand.', retryable: true }
}
