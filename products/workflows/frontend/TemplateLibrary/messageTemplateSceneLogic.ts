import { MakeLogicType, afterMount, beforeUnmount, connect, kea, path, props, selectors } from 'kea'

import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { sidePanelStateLogic } from '~/layout/navigation-3000/sidepanel/sidePanelStateLogic'
import { FileSystemIconType } from '~/queries/schema/schema-general'
import { Breadcrumb, SidePanelTab } from '~/types'

import { welcomeHeadlineLogic } from 'products/posthog_ai/frontend/api/logics'

const WELCOME_HEADLINE_PROVIDER_ID = 'message-template-editor'

export interface MessageTemplateSceneLogicProps {
    id: string
    messageId?: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface messageTemplateSceneLogicValues {
    breadcrumbs: Breadcrumb[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface messageTemplateSceneLogicActions {
    deregisterHeadline: (providerId: string) => {
        providerId: string
    } // welcomeHeadlineLogic
    registerHeadline: (
        providerId: string,
        headline: string
    ) => {
        headline: string
        providerId: string
    } // welcomeHeadlineLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface messageTemplateSceneLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        breadcrumbs: (id: string) => Breadcrumb[]
    }
}

export type messageTemplateSceneLogicType = MakeLogicType<
    messageTemplateSceneLogicValues,
    messageTemplateSceneLogicActions,
    MessageTemplateSceneLogicProps,
    messageTemplateSceneLogicMeta
>

export const messageTemplateSceneLogic = kea<messageTemplateSceneLogicType>([
    path(['products', 'workflows', 'frontend', 'messageTemplateSceneLogic']),
    props({} as MessageTemplateSceneLogicProps),
    connect(() => ({
        actions: [welcomeHeadlineLogic, ['registerHeadline', 'deregisterHeadline']],
    })),
    selectors({
        breadcrumbs: [
            (_, p) => [p.id],
            (id: string): Breadcrumb[] => {
                return [
                    {
                        key: [Scene.Workflows, 'library'],
                        name: 'Library',
                        path: urls.workflows('library'),
                        iconType: 'workflows',
                    },
                    ...(id === 'new'
                        ? [
                              {
                                  key: 'new-template',
                                  name: 'New template',
                                  path: urls.workflowsLibraryTemplateNew(),
                                  iconType: 'workflows' as FileSystemIconType,
                              },
                          ]
                        : [
                              {
                                  key: 'edit-template',
                                  name: 'Manage template',
                                  path: urls.workflowsLibraryTemplate(id),
                                  iconType: 'workflows' as FileSystemIconType,
                              },
                          ]),
                ]
            },
        ],
    }),
    afterMount(({ actions, props }) => {
        // The template editor is an AI-first surface: surface the assistant alongside the canvas.
        if (!sidePanelStateLogic.findMounted()?.values.sidePanelOpen) {
            sidePanelStateLogic.findMounted()?.actions.openSidePanel(SidePanelTab.Max)
        }
        actions.registerHeadline(
            WELCOME_HEADLINE_PROVIDER_ID,
            props.id === 'new' ? 'What template would you like to build?' : 'How can we improve this email template?'
        )
    }),
    beforeUnmount(({ actions }) => {
        actions.deregisterHeadline(WELCOME_HEADLINE_PROVIDER_ID)
    }),
])
