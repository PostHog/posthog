// pinned: the `scout-tags` value the canonical workflows scouts declare in their SKILL.md frontmatter
export const WORKFLOWS_SCOUT_TAG = 'workflows'
const SUGGESTIONS_PAGE_SIZE = 20

export type WorkflowsSelfDrivingAvailability = 'unknown' | 'available' | 'unavailable' | 'error'

async function fetchWorkflowsScoutConfigs(teamId: number | null): Promise<SignalScoutConfigApi[]> {
    return signalsScoutConfigList(String(teamId), { tags: WORKFLOWS_SCOUT_TAG })
}

