export const workflowsSelfDrivingLogic = kea<workflowsSelfDrivingLogicType>([
    path(['products', 'workflows', 'frontend', 'SelfDriving', 'workflowsSelfDrivingLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        turnOnSelfDriving: true,
        turnOnSelfDrivingFinished: true,
        updateScoutConfig: (configId: string, updates: PatchedSignalScoutConfigUpdateApi) => ({ configId, updates }),
        setScoutUpdating: (configId: string, updating: boolean) => ({ configId, updating }),
    }),
    loaders(({ values }) => ({
        scoutConfigs: [
            null as SignalScoutConfigApi[] | null,
            {
                loadScoutConfigs: async () => fetchWorkflowsScoutConfigs(values.currentTeamId),
                // The coordinator seeds a canonical scout's config on its next tick, so a project that opens the
                // tab before that asks the fleet sync to materialize it. A withheld scout stays absent after the sync.
                syncScoutConfigs: async () => {
                    const fleet = await signalsScoutConfigSync(String(values.currentTeamId))
                    return fleet.filter((config) => (config.tags ?? []).includes(WORKFLOWS_SCOUT_TAG))
                },
            },
        ],
        suggestions: [
            null as SignalReportListApi[] | null,
            {
                loadSuggestions: async () => {
                    if (values.scoutSkillNames.length === 0) {
                        return []
                    }
                    const page = await signalsReportsList(String(values.currentTeamId), {
                        scout: values.scoutSkillNames.join(','),
                        sort: 'newest',
                        limit: SUGGESTIONS_PAGE_SIZE,
                    })
                    return page.results
                },
            },
        ],
    })),
    reducers({
        syncAttempted: [false, { syncScoutConfigs: () => true }],
        scoutConfigsFailed: [false, { loadScoutConfigs: () => false, loadScoutConfigsFailure: () => true }],
        suggestionsFailed: [false, { loadSuggestions: () => false, loadSuggestionsFailure: () => true }],
        turningOn: [false, { turnOnSelfDriving: () => true, turnOnSelfDrivingFinished: () => false }],
        updatingScoutIds: [
            [] as string[],
            {
                setScoutUpdating: (state, { configId, updating }) => {
                    const others = state.filter((id) => id !== configId)
                    return updating ? [...others, configId] : others
                },
            },
        ],
    }),
    selectors({
        availability: [
            (s) => [s.scoutConfigs, s.syncAttempted, s.scoutConfigsFailed],
            (
                scoutConfigs: SignalScoutConfigApi[] | null,
                syncAttempted: boolean,
                scoutConfigsFailed: boolean
            ): WorkflowsSelfDrivingAvailability => {
                if (scoutConfigs === null) {
                    return scoutConfigsFailed ? 'error' : 'unknown'
                }
                if (scoutConfigs.length > 0) {
                    return 'available'
                }
                return syncAttempted ? 'unavailable' : 'unknown'
            },
        ],
        selfDrivingEnabled: [
            (s) => [s.scoutConfigs],
            (scoutConfigs: SignalScoutConfigApi[] | null): boolean =>
                (scoutConfigs ?? []).some((config) => config.enabled),
        ],
        scoutSkillNames: [
            (s) => [s.scoutConfigs],
            (scoutConfigs: SignalScoutConfigApi[] | null): string[] =>
                (scoutConfigs ?? []).map((config) => config.skill_name),
        ],
    }),
    listeners(({ actions, values }) => ({
        loadScoutConfigsSuccess: ({ scoutConfigs }) => {
            if ((scoutConfigs ?? []).length === 0) {
                if (!values.syncAttempted) {
                    actions.syncScoutConfigs()
                }
                return
            }
            actions.loadSuggestions()
        },
        syncScoutConfigsSuccess: ({ scoutConfigs }) => {
            if ((scoutConfigs ?? []).length > 0) {
                actions.loadSuggestions()
            }
        },
        turnOnSelfDriving: async () => {
            const disabled = (values.scoutConfigs ?? []).filter((config) => !config.enabled)
            try {
                for (const config of disabled) {
                    await signalsScoutConfigUpdate(String(values.currentTeamId), config.id, { enabled: true })
                }
                actions.loadScoutConfigsSuccess(await fetchWorkflowsScoutConfigs(values.currentTeamId))
            } catch {
                lemonToast.error('Could not turn on Self-driving. Try again, and if it keeps failing contact support.')
            } finally {
                actions.turnOnSelfDrivingFinished()
            }
        },
        updateScoutConfig: async ({ configId, updates }) => {
            actions.setScoutUpdating(configId, true)
            try {
                const updated = await signalsScoutConfigUpdate(String(values.currentTeamId), configId, updates)
                actions.loadScoutConfigsSuccess(
                    (values.scoutConfigs ?? []).map((config) => (config.id === configId ? updated : config))
                )
            } catch {
                lemonToast.error('Could not save the scout settings. Try again.')
            } finally {
                actions.setScoutUpdating(configId, false)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadScoutConfigs()
    }),
])
