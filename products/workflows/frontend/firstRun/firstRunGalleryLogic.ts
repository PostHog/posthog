// pinned: the id of the global welcome sequence in products/workflows/backend/templates/
export const WELCOME_SEQUENCE_TEMPLATE_ID = '019b6f44-f9a3-0000-c4a7-b8050d25d690'

// pinned: search param on the Workflows tab that addresses Make it yours, so bookmarks and reloads return to it
export const FIRST_RUN_TEMPLATE_PARAM = 'template'

export type GalleryFilter = 'picked' | 'all'

export interface StartableTemplate {
    template: HogFlowTemplate
    startsOn: HogFlowTemplateStartsOnApi
}

export interface GalleryTemplate extends StartableTemplate {
    matchedEvent: string | null
    ready: boolean
}

export interface RecommendedStarter {
    templateId: string
    reason: string
}

function isEmailTemplate(
    template: HogFlowTemplateApi
): template is HogFlowTemplateApi & { starts_on: HogFlowTemplateStartsOnApi } {
    return template.scope === 'global' && !!template.starts_on
}

function eventsToLookUp(emailTemplates: StartableTemplate[]): string[] {
    return [...new Set(emailTemplates.flatMap(({ startsOn }) => startsOn.events))]
}

function fitTemplate(
    { template, startsOn }: StartableTemplate,
    seenEvents: Set<string>,
    projectIngestedEvents: boolean
): GalleryTemplate {
    if (startsOn.kind === 'schedule') {
        return { template, startsOn, matchedEvent: null, ready: projectIngestedEvents }
    }
    const matchedEvent = startsOn.events.find((event) => seenEvents.has(event)) ?? null
    return { template, startsOn, matchedEvent, ready: matchedEvent !== null }
}

function recommend(galleryTemplates: GalleryTemplate[]): RecommendedStarter | null {
    const welcome = galleryTemplates.find(({ template }) => template.id === WELCOME_SEQUENCE_TEMPLATE_ID)
    if (welcome?.ready) {
        return {
            templateId: welcome.template.id,
            reason: 'Every new signup gets it, and your app already sends a signup event.',
        }
    }
    const firstReady = galleryTemplates.find(({ ready }) => ready)
    return firstReady
        ? { templateId: firstReady.template.id, reason: 'It works with the events your app sends today.' }
        : null
}

