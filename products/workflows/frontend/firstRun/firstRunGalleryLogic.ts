export const firstRunGalleryLogic = kea<firstRunGalleryLogicType>([
    path(['products', 'workflows', 'frontend', 'firstRun', 'firstRunGalleryLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], teamLogic, ['currentTeam'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        setFilter: (filter: GalleryFilter) => ({ filter }),
        pickTemplate: (templateId: string) => ({ templateId }),
    }),
    loaders(({ values }) => ({
        emailTemplates: [
            null as StartableTemplate[] | null,
            {
                loadEmailTemplates: async (): Promise<StartableTemplate[]> => {
                    if (!values.firstRunEnabled) {
                        return []
                    }
                    const response = await hogFlowTemplatesList(String(values.currentProjectId))
                    return response.results.filter(isEmailTemplate).map((template) => ({
                        template: template as unknown as HogFlowTemplate,
                        startsOn: template.starts_on,
                    }))
                },
            },
        ],
        seenEvents: [
            null as string[] | null,
            {
                loadSeenEvents: async (names: string[]): Promise<string[]> => {
                    if (!values.firstRunEnabled || names.length === 0) {
                        return []
                    }
                    const response = await eventDefinitionsList(String(values.currentProjectId), {
                        names,
                        limit: names.length,
                    })
                    // A definition can exist before its event arrives, for example one the Wizard planned.
                    return response.results.filter(({ last_seen_at }) => last_seen_at !== null).map(({ name }) => name)
                },
            },
        ],
    })),
    reducers({
        filter: ['picked' as GalleryFilter, { setFilter: (_, { filter }) => filter }],
        galleryLoadFailed: [
            false,
            {
                loadEmailTemplates: () => false,
                loadEmailTemplatesFailure: () => true,
                loadSeenEventsFailure: () => true,
            },
        ],
    }),
    selectors({
        firstRunEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.WORKFLOWS_FIRST_RUN],
        ],
        galleryTemplates: [
            (s) => [s.emailTemplates, s.seenEvents, s.currentTeam],
            (
                emailTemplates: StartableTemplate[] | null,
                seenEvents: string[] | null,
                currentTeam: TeamType | TeamPublicType | null
            ): GalleryTemplate[] | null => {
                if (!emailTemplates || !seenEvents) {
                    return null
                }
                const seen = new Set(seenEvents)
                return emailTemplates.map((emailTemplate) =>
                    fitTemplate(emailTemplate, seen, !!currentTeam?.ingested_event)
                )
            },
        ],
        recommendedStarter: [
            (s) => [s.galleryTemplates],
            (galleryTemplates: GalleryTemplate[] | null): RecommendedStarter | null =>
                galleryTemplates ? recommend(galleryTemplates) : null,
        ],
        readyTemplates: [
            (s) => [s.galleryTemplates],
            (galleryTemplates: GalleryTemplate[] | null): GalleryTemplate[] =>
                (galleryTemplates ?? []).filter(({ ready }) => ready),
        ],
        activeFilter: [
            (s) => [s.filter, s.readyTemplates],
            (filter: GalleryFilter, readyTemplates: GalleryTemplate[]): GalleryFilter =>
                readyTemplates.length === 0 ? 'all' : filter,
        ],
        shownTemplates: [
            (s) => [s.galleryTemplates, s.recommendedStarter, s.activeFilter],
            (
                galleryTemplates: GalleryTemplate[] | null,
                recommendedStarter: RecommendedStarter | null,
                activeFilter: GalleryFilter
            ): GalleryTemplate[] => {
                const rank = ({ template, ready }: GalleryTemplate): number =>
                    template.id === recommendedStarter?.templateId ? 0 : ready ? 1 : 2
                return (galleryTemplates ?? [])
                    .filter(({ ready }) => activeFilter === 'all' || ready)
                    .sort((a, b) => rank(a) - rank(b))
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        loadEmailTemplatesSuccess: ({ emailTemplates }) => {
            if (values.firstRunEnabled) {
                actions.loadSeenEvents(eventsToLookUp(emailTemplates))
            }
        },
        loadSeenEventsSuccess: () => {
            if (!values.firstRunEnabled) {
                return
            }
            posthog.capture('workflows first run gallery shown', {
                ready_count: values.readyTemplates.length,
                recommended_template_id: values.recommendedStarter?.templateId ?? null,
            })
        },
        pickTemplate: ({ templateId }) => {
            if (!values.firstRunEnabled) {
                return
            }
            const picked = values.galleryTemplates?.find(({ template }) => template.id === templateId)
            if (!picked) {
                return
            }
            posthog.capture('workflows first run template picked', {
                template_id: templateId,
                recommended: templateId === values.recommendedStarter?.templateId,
                ready: picked.ready,
            })
            router.actions.push(urls.workflows(), { [FIRST_RUN_TEMPLATE_PARAM]: templateId })
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.firstRunEnabled) {
            actions.loadEmailTemplates()
        }
    }),
])
