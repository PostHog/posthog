import { MakeLogicType, afterMount, connect, kea, key, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { integrationsLogic } from 'lib/integrations/integrationsLogic'
import { isSandboxEmailSender } from 'lib/integrations/utils'
import { projectLogic } from 'scenes/projectLogic'

import type { IntegrationType } from '~/types'

import { hogFlowsEmailReachRetrieve } from '../generated/api'
import type { EmailReachApi } from '../generated/api.schemas'

export interface FirstRunReachLogicProps {
    senderIntegrationId: number | null
}

export type OwnDomainState = 'none' | 'verifying'

export interface FirstRunReach {
    senderAddress: string
    counts: { reached: number; notReachedYet: number } | null
    ownDomain: OwnDomainState
}

function isVerified(integration: IntegrationType): boolean {
    return integration.config?.verified === true
}

