export type firstRunReachLogicType = MakeLogicType<
    firstRunReachLogicValues,
    firstRunReachLogicActions,
    FirstRunReachLogicProps,
    firstRunReachLogicMeta
>

export const firstRunReachLogic = kea<firstRunReachLogicType>([
    props({} as FirstRunReachLogicProps),
    key((props: FirstRunReachLogicProps): string => String(props.senderIntegrationId ?? 'none')),
    path((key) => ['products', 'workflows', 'frontend', 'firstRun', 'firstRunReachLogic', key]),
    connect(() => ({
        values: [integrationsLogic, ['integrations', 'ownEmailIntegrations'], projectLogic, ['currentProjectId']],
    })),
    loaders(({ values }) => ({
        emailReach: [
            null as EmailReachApi | null,
            {
                loadEmailReach: async (): Promise<EmailReachApi | null> => {
                    try {
                        return await hogFlowsEmailReachRetrieve(String(values.currentProjectId))
                    } catch {
                        return null
                    }
                },
            },
        ],
    })),
    selectors({
        ownDomain: [
            (s) => [s.ownEmailIntegrations],
            (ownEmailIntegrations: IntegrationType[]): OwnDomainState | 'verified' => {
                if (ownEmailIntegrations.some(isVerified)) {
                    return 'verified'
                }
                return ownEmailIntegrations.length > 0 ? 'verifying' : 'none'
            },
        ],
        reach: [
            (s) => [
                s.integrations,
                s.ownDomain,
                s.emailReach,
                (_, props: FirstRunReachLogicProps) => props.senderIntegrationId,
            ],
            (
                integrations: IntegrationType[] | null,
                ownDomain: OwnDomainState | 'verified',
                emailReach: EmailReachApi | null,
                senderIntegrationId: number | null
            ): FirstRunReach | null => {
                const sender = integrations?.find((integration) => integration.id === senderIntegrationId)
                if (!sender || !isSandboxEmailSender(sender) || ownDomain === 'verified') {
                    return null
                }
                return {
                    senderAddress: sender.config.email,
                    counts: emailReach
                        ? { reached: emailReach.verified_member_count, notReachedYet: emailReach.project_email_count }
                        : null,
                    ownDomain,
                }
            },
        ],
    }),
    afterMount(({ actions }) => actions.loadEmailReach()),
])
