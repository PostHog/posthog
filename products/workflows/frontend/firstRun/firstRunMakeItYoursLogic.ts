export const firstRunMakeItYoursLogic: LogicWrapper<firstRunMakeItYoursLogicType> = kea<firstRunMakeItYoursLogicType>([
    props({} as FirstRunMakeItYoursLogicProps),
    key((props) => props.templateId),
    path((key) => ['products', 'workflows', 'frontend', 'firstRun', 'firstRunMakeItYoursLogic', key]),
    connect(() => ({
        values: [
            firstRunGalleryLogic,
            ['galleryTemplates', 'galleryLoadFailed'],
            firstRunSenderLogic,
            ['firstRunSender', 'firstRunSenderLoading', 'firstRunEnabled'],
            projectLogic,
            ['currentProjectId'],
            teamLogic,
            ['currentTeamId'],
            userLogic,
            ['user'],
        ],
    })),
    actions({
        openEmail: (emailId: string) => ({ emailId }),
        setOpenEmailId: (emailId: string) => ({ emailId }),
        editEmail: (emailId: string, email: EmailTemplate) => ({ emailId, email }),
        setEnableWorkflow: (enabled: boolean) => ({ enabled }),
        setCreateError: (error: string) => ({ error }),
        markTestSendFailed: true,
    }),
    // The loaders catch their own errors so the screen shows them in place, instead of the generic failure toast.
    loaders(({ values, props, actions }) => ({
        testSendResult: [
            null as HogflowTestResult | null,
            {
                sendTest: async (_: void, breakpoint): Promise<HogflowTestResult | null> => {
                    await waitForPendingCanvasEdit(breakpoint)
                    const { openEmail, firstRunSender, user, pickedTemplate } = values
                    if (!openEmail || !firstRunSender || !user?.email) {
                        return null
                    }
                    try {
                        return await api.hogFlows.createTestInvocation(
                            'new',
                            buildFirstRunTestSend({
                                email: openEmail.email,
                                sender: firstRunSender,
                                recipientEmail: user.email,
                                workflowName: pickedTemplate?.template.name || 'Test email',
                                teamId: values.currentTeamId,
                            })
                        )
                    } catch {
                        actions.markTestSendFailed()
                        return null
                    }
                },
            },
        ],
        createdWorkflow: [
            null as HogFlowApi | null,
            {
                createWorkflow: async (_: void, breakpoint): Promise<HogFlowApi | null> => {
                    await waitForPendingCanvasEdit(breakpoint)
                    if (!values.firstRunEnabled || !values.pickedTemplate) {
                        return null
                    }
                    const workflow = buildFirstRunWorkflow({
                        template: values.pickedTemplate.template,
                        matchedEvent: values.pickedTemplate.matchedEvent,
                        edits: values.edits,
                        sender: values.firstRunSender,
                        enabled: values.enableWorkflow,
                    })
                    try {
                        const created = await hogFlowsCreate(
                            String(values.currentProjectId),
                            workflow as Parameters<typeof hogFlowsCreate>[1]
                        )
                        posthog.capture('workflows first run workflow created', {
                            template_id: props.templateId,
                            enabled: values.enableWorkflow,
                        })
                        return created
                    } catch (error: any) {
                        actions.setCreateError(error?.detail || error?.message || 'Something went wrong')
                        return null
                    }
                },
            },
        ],
    })),
    reducers({
        openEmailIdOverride: [null as string | null, { setOpenEmailId: (_, { emailId }) => emailId }],
        edits: [
            {} as Record<string, EmailTemplate>,
            { editEmail: (state, { emailId, email }) => ({ ...state, [emailId]: email }) },
        ],
        enableWorkflowChoice: [true, { setEnableWorkflow: (_, { enabled }) => enabled }],
        testSendFailed: [false, { sendTest: () => false, markTestSendFailed: () => true }],
        createError: [
            null as string | null,
            {
                createWorkflow: () => null,
                setCreateError: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        pickedTemplate: [
            (s, p) => [s.galleryTemplates, p.templateId],
            (galleryTemplates: GalleryTemplate[] | null, templateId: string): GalleryTemplate | null =>
                galleryTemplates?.find(({ template }) => template.id === templateId) ?? null,
        ],
        templateEmails: [
            (s) => [s.pickedTemplate],
            (pickedTemplate: GalleryTemplate | null): TemplateEmail[] =>
                pickedTemplate
                    ? listTemplateEmails(pickedTemplate.template.actions, pickedTemplate.template.edges)
                    : [],
        ],
        openEmailId: [
            (s) => [s.openEmailIdOverride, s.templateEmails],
            (override: string | null, templateEmails: TemplateEmail[]): string | null =>
                templateEmails.find(({ id }) => id === override)?.id ?? templateEmails[0]?.id ?? null,
        ],
        openEmail: [
            (s) => [s.templateEmails, s.openEmailId, s.edits],
            (
                templateEmails: TemplateEmail[],
                openEmailId: string | null,
                edits: Record<string, EmailTemplate>
            ): OpenEmail | null => {
                const templateEmail = templateEmails.find(({ id }) => id === openEmailId)
                if (!templateEmail) {
                    return null
                }
                const edit = edits[templateEmail.id]
                return { ...templateEmail, email: edit ?? templateEmail.email, edited: !!edit }
            },
        ],
        openEmailPosition: [
            (s) => [s.templateEmails, s.openEmailId],
            (templateEmails: TemplateEmail[], openEmailId: string | null): OpenEmailPosition | null => {
                const index = templateEmails.findIndex(({ id }) => id === openEmailId)
                return index === -1 ? null : { index: index + 1, total: templateEmails.length }
            },
        ],
        editedEmailIds: [(s) => [s.edits], (edits: Record<string, EmailTemplate>): string[] => Object.keys(edits)],
        createDisabledReason: [
            (s) => [s.firstRunEnabled],
            (firstRunEnabled: boolean): string | null =>
                firstRunEnabled
                    ? getAccessControlDisabledReason(AccessControlResourceType.Workflow, AccessControlLevel.Editor)
                    : 'First-run setup is not available',
        ],
        senderDisabledReason: [
            (s) => [s.firstRunSenderLoading, s.firstRunSender],
            (firstRunSenderLoading: boolean, firstRunSender: FirstRunSender | null): string | null => {
                if (firstRunSender) {
                    return null
                }
                return firstRunSenderLoading ? 'Checking your email senders' : 'Connect an email sender first'
            },
        ],
        sendTestDisabledReason: [
            (s) => [s.createDisabledReason, s.senderDisabledReason],
            (createDisabledReason: string | null, senderDisabledReason: string | null): string | null =>
                createDisabledReason ?? senderDisabledReason,
        ],
        enableDisabledReason: [
            (s) => [s.createDisabledReason, s.senderDisabledReason],
            (createDisabledReason: string | null, senderDisabledReason: string | null): string | null =>
                createDisabledReason ?? senderDisabledReason,
        ],
        enableWorkflow: [
            (s) => [s.enableWorkflowChoice, s.enableDisabledReason],
            (enableWorkflowChoice: boolean, enableDisabledReason: string | null): boolean =>
                enableWorkflowChoice && !enableDisabledReason,
        ],
        testSendOutcome: [
            (s) => [s.testSendResult, s.testSendFailed, s.user],
            (
                testSendResult: HogflowTestResult | null,
                testSendFailed: boolean,
                user: UserType | null
            ): TestSendOutcome | null => {
                if (testSendFailed) {
                    return { kind: 'failed' }
                }
                if (!testSendResult) {
                    return null
                }
                const skipReason = findTestSendSkipReason(testSendResult)
                if (skipReason) {
                    return { kind: 'skipped', reason: skipReason }
                }
                if (testSendResult.status === 'success') {
                    return { kind: 'sent', recipient: user?.email ?? '' }
                }
                if (testSendResult.status === 'skipped') {
                    return {
                        kind: 'skipped',
                        reason:
                            testSendResult.logs?.map((log) => log.message).join(' ') ||
                            'The email step was skipped, so nothing was sent.',
                    }
                }
                return { kind: 'failed' }
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        openEmail: async ({ emailId }, breakpoint) => {
            await waitForPendingCanvasEdit(breakpoint)
            actions.setOpenEmailId(emailId)
        },
        createWorkflowSuccess: ({ createdWorkflow }) => {
            if (!createdWorkflow) {
                return
            }
            rememberFirstRunWorkflow(createdWorkflow.id)
            if (createdWorkflow.status === 'active') {
                globalSetupLogic.findMounted()?.actions.markTaskAsCompleted(SetupTaskId.LaunchWorkflow)
            }
            router.actions.push(urls.workflow(createdWorkflow.id, 'workflow'))
        },
        sendTestSuccess: () => {
            const outcome = values.testSendOutcome
            if (outcome?.kind === 'sent' || outcome?.kind === 'skipped') {
                posthog.capture('workflows first run test sent', { skipped: outcome.kind === 'skipped' })
            }
            if (outcome?.kind === 'sent') {
                globalSetupLogic.findMounted()?.actions.markTaskAsCompleted(SetupTaskId.SendWorkflowTestEmail)
            }
        },
    })),
])
