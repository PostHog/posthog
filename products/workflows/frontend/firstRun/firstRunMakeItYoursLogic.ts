// The templater exports a canvas edit 500ms after the last change and flags the wait in its cache. Switching,
// sending or creating inside that window would act on the email without the edit, so every one of them waits.
async function waitForPendingCanvasEdit(breakpoint: BreakPointFunction): Promise<void> {
    while (emailTemplaterLogic.findMounted()?.cache.pendingDesignEdit) {
        await breakpoint(100)
    }
}

