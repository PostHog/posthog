import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { projectLogic } from 'scenes/projectLogic'

import { propertyDefinitionsList } from '~/generated/core/api'

import { firstRunGalleryLogic, GalleryTemplate, WELCOME_SEQUENCE_TEMPLATE_ID } from './firstRunGalleryLogic'

// pinned: analytics property values
export type MissingData = 'signup_event' | 'email'

const EMAIL_PERSON_PROPERTY = 'email'

function findWelcomeTemplate(galleryTemplates: GalleryTemplate[] | null): GalleryTemplate | null {
    return galleryTemplates?.find(({ template }) => template.id === WELCOME_SEQUENCE_TEMPLATE_ID) ?? null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstRunAgentHelpLogicValues {
    firstRunEnabled: boolean // firstRunGalleryLogic
    galleryTemplates: GalleryTemplate[] | null // firstRunGalleryLogic
    currentProjectId: number | null // projectLogic
    hasEmailProperty: boolean | null
    hasEmailPropertyLoading: boolean
    missingData: MissingData | null
    signupEventSeen: boolean | null
    wizardShown: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstRunAgentHelpLogicActions {
    loadSeenEventsSuccess: (
        seenEvents: string[],
        payload?: string[] | undefined
    ) => {
        payload?: string[]
        seenEvents: string[]
    } // firstRunGalleryLogic
    loadEmailProperty: () => any
    loadEmailPropertyFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadEmailPropertySuccess: (
        hasEmailProperty: boolean,
        payload?: any
    ) => {
        hasEmailProperty: boolean
        payload?: any
    }
    reportAgentHelpShown: () => {
        value: true
    }
    reportPromptCopied: () => {
        value: true
    }
    setWizardShown: (wizardShown: boolean) => {
        wizardShown: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstRunAgentHelpLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        signupEventSeen: (galleryTemplates: GalleryTemplate[] | null) => boolean | null
        missingData: (
            signupEventSeen: boolean | null,
            hasEmailProperty: boolean | null,
            firstRunEnabled: any
        ) => MissingData | null
    }
}

export type firstRunAgentHelpLogicType = MakeLogicType<
    firstRunAgentHelpLogicValues,
    firstRunAgentHelpLogicActions,
    Record<string, any>,
    firstRunAgentHelpLogicMeta
>

export const firstRunAgentHelpLogic = kea<firstRunAgentHelpLogicType>([
    path(['products', 'workflows', 'frontend', 'firstRun', 'firstRunAgentHelpLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], firstRunGalleryLogic, ['galleryTemplates', 'firstRunEnabled']],
        actions: [firstRunGalleryLogic, ['loadSeenEventsSuccess']],
    })),
    actions({
        reportAgentHelpShown: true,
        reportPromptCopied: true,
        setWizardShown: (wizardShown: boolean) => ({ wizardShown }),
    }),
    loaders(({ values }) => ({
        hasEmailProperty: [
            null as boolean | null,
            {
                loadEmailProperty: async (): Promise<boolean> => {
                    if (!values.firstRunEnabled) {
                        return false
                    }
                    const response = await propertyDefinitionsList(String(values.currentProjectId), {
                        type: 'person',
                        properties: EMAIL_PERSON_PROPERTY,
                        limit: 1,
                    })
                    return response.results.length > 0
                },
            },
        ],
    })),
    reducers({
        wizardShown: [false, { setWizardShown: (_, { wizardShown }) => wizardShown }],
    }),
    selectors({
        signupEventSeen: [
            (s) => [s.galleryTemplates],
            (galleryTemplates: GalleryTemplate[] | null): boolean | null => {
                const welcome = findWelcomeTemplate(galleryTemplates)
                return welcome ? welcome.matchedEvent !== null : null
            },
        ],
        missingData: [
            (s) => [s.signupEventSeen, s.hasEmailProperty, s.firstRunEnabled],
            (
                signupEventSeen: boolean | null,
                hasEmailProperty: boolean | null,
                firstRunEnabled: boolean
            ): MissingData | null => {
                if (!firstRunEnabled) {
                    return null
                }
                if (signupEventSeen === false) {
                    return 'signup_event'
                }
                return signupEventSeen && hasEmailProperty === false ? 'email' : null
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadSeenEventsSuccess: () => actions.reportAgentHelpShown(),
        loadEmailPropertySuccess: () => actions.reportAgentHelpShown(),
        reportAgentHelpShown: () => {
            if (!values.missingData || cache.agentHelpReported) {
                return
            }
            cache.agentHelpReported = true
            posthog.capture('workflows first run agent help shown', { missing: values.missingData })
        },
        reportPromptCopied: () => {
            if (values.firstRunEnabled) {
                posthog.capture('workflows first run agent prompt copied', { missing: values.missingData })
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.firstRunEnabled) {
            actions.loadEmailProperty()
        }
    }),
])
