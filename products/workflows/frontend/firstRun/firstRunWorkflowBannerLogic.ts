import { router } from 'kea-router'
import { subscriptions } from 'kea-subscriptions'

import { globalSetupLogic } from 'lib/components/ProductSetup'
import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic, FeatureFlagsSet } from 'lib/logic/featureFlagLogic'
import { urls } from 'scenes/urls'

import type { HogFlow } from '../Workflows/hogflows/types'
import { WorkflowLogicProps, workflowLogic } from '../Workflows/workflowLogic'
import { getFirstRunWorkflowId } from './firstRunWorkflowStorage'

export type FirstRunBannerState = 'draft' | 'sending'

const ENABLE_BUTTON_SELECTOR = '[data-attr="workflow-launch"]'

function bannerForStatus(status: HogFlow['status']): FirstRunBannerState | null {
    if (status === 'draft') {
        return 'draft'
    }
    return status === 'active' ? 'sending' : null
}

