import { MakeLogicType, afterMount, beforeUnmount, connect, kea, listeners, path, props, propsChanged } from 'kea'

import { navPanelProductPushWelcomeLogic } from 'lib/components/NavPanelAdvertisement/navPanelProductPushWelcomeLogic'
import type { ProductSetupStatus } from 'lib/components/ProductEmptyState/types'
import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'

import type { FeatureFlagsSet } from '../../../../frontend/src/lib/logic/featureFlagLogic'

const WELCOME_HOLDER = 'workflows-first-run'

export interface FirstRunWelcomeHoldLogicProps {
    setupStatus: ProductSetupStatus
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstRunWelcomeHoldLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstRunWelcomeHoldLogicActions {
    setFeatureFlags: (
        flags: string[],
        variants: Record<string, boolean | string>
    ) => {
        flags: string[]
        variants: Record<string, boolean | string>
    } // featureFlagLogic
    holdWelcome: (holder: string) => {
        holder: string
    } // navPanelProductPushWelcomeLogic
    releaseWelcome: (holder: string) => {
        holder: string
    } // navPanelProductPushWelcomeLogic
}

export type firstRunWelcomeHoldLogicType = MakeLogicType<
    firstRunWelcomeHoldLogicValues,
    firstRunWelcomeHoldLogicActions,
    FirstRunWelcomeHoldLogicProps
>

function updateWelcomeHold({ actions, props, values }: firstRunWelcomeHoldLogicType): void {
    if (
        values.featureFlags[FEATURE_FLAGS.WORKFLOWS_FIRST_RUN] &&
        (props.setupStatus === 'loading' || props.setupStatus === 'needs-setup')
    ) {
        actions.holdWelcome(WELCOME_HOLDER)
    } else {
        actions.releaseWelcome(WELCOME_HOLDER)
    }
}

export const firstRunWelcomeHoldLogic = kea<firstRunWelcomeHoldLogicType>([
    props({} as FirstRunWelcomeHoldLogicProps),
    path(['products', 'workflows', 'frontend', 'firstRun', 'firstRunWelcomeHoldLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
        actions: [
            navPanelProductPushWelcomeLogic,
            ['holdWelcome', 'releaseWelcome'],
            featureFlagLogic,
            ['setFeatureFlags'],
        ],
    })),
    listeners((logic) => ({ setFeatureFlags: () => updateWelcomeHold(logic) })),
    afterMount(updateWelcomeHold),
    propsChanged(updateWelcomeHold),
    beforeUnmount(({ actions }) => {
        actions.releaseWelcome(WELCOME_HOLDER)
    }),
])
