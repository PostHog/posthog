import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { ApiError } from 'lib/api'
import { getAccessControlDisabledReason } from 'lib/utils/accessControlUtils'
import { Scene } from 'scenes/sceneTypes'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { AccessControlLevel, AccessControlResourceType, Breadcrumb } from '~/types'

import {
    transactionalCodeEmailsPartialUpdate,
    transactionalCodeEmailsRetrieve,
} from 'products/messaging/frontend/generated/api'
import type { CodeEmailApi, PatchedCodeEmailUpdateApi } from 'products/messaging/frontend/generated/api.schemas'

export interface CodeEmailLogicProps {
    id: string
}

export type CodeEmailTab = 'metrics' | 'sends' | 'api'

export type CodeEmailLoadState = 'loading' | 'loaded' | 'not-found' | 'failed'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface codeEmailLogicValues {
    currentTeamId: number | null // teamLogic
    breadcrumbs: Breadcrumb[]
    codeEmail: CodeEmailApi | null
    editDisabledReason: string | null
    loadState: CodeEmailLoadState
    saving: boolean
    tab: CodeEmailTab
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface codeEmailLogicActions {
    codeEmailLoadFailed: () => {
        value: true
    }
    codeEmailLoaded: (codeEmail: CodeEmailApi) => {
        codeEmail: CodeEmailApi
    }
    codeEmailNotFound: () => {
        value: true
    }
    loadCodeEmail: () => {
        value: true
    }
    savesSettled: () => {
        value: true
    }
    setTab: (tab: CodeEmailTab) => {
        tab: CodeEmailTab
    }
    showSends: (searchParams: Record<string, string>) => {
        searchParams: Record<string, string>
    }
    updateCodeEmail: (fields: PatchedCodeEmailUpdateApi) => {
        fields: PatchedCodeEmailUpdateApi
    }
    updateCodeEmailFailure: (error: string) => {
        error: string
    }
    updateCodeEmailSuccess: (
        codeEmail: CodeEmailApi,
        fields: PatchedCodeEmailUpdateApi
    ) => {
        codeEmail: CodeEmailApi
        fields: PatchedCodeEmailUpdateApi
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface codeEmailLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        editDisabledReason: (codeEmail: CodeEmailApi | null) => string | null
        breadcrumbs: (codeEmail: CodeEmailApi | null, arg: any) => Breadcrumb[]
    }
}

export type codeEmailLogicType = MakeLogicType<
    codeEmailLogicValues,
    codeEmailLogicActions,
    CodeEmailLogicProps,
    codeEmailLogicMeta
>

export const codeEmailLogic = kea<codeEmailLogicType>([
    props({} as CodeEmailLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'workflows', 'frontend', 'Transactional', 'code', 'codeEmailLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        setTab: (tab: CodeEmailTab) => ({ tab }),
        showSends: (searchParams: Record<string, string>) => ({ searchParams }),
        loadCodeEmail: true,
        codeEmailLoaded: (codeEmail: CodeEmailApi) => ({ codeEmail }),
        codeEmailNotFound: true,
        codeEmailLoadFailed: true,
        updateCodeEmail: (fields: PatchedCodeEmailUpdateApi) => ({ fields }),
        updateCodeEmailSuccess: (codeEmail: CodeEmailApi, fields: PatchedCodeEmailUpdateApi) => ({
            codeEmail,
            fields,
        }),
        updateCodeEmailFailure: (error: string) => ({ error }),
        savesSettled: true,
    }),
    reducers({
        tab: ['metrics' as CodeEmailTab, { setTab: (_, { tab }) => tab, showSends: () => 'sends' }],
        codeEmail: [
            null as CodeEmailApi | null,
            {
                codeEmailLoaded: (_, { codeEmail }) => codeEmail,
                codeEmailNotFound: () => null,
                // Edits show at once, so an edit made while a save is in flight starts from the newest values.
                updateCodeEmail: (state, { fields }) => (state ? { ...state, ...fields } : state),
                updateCodeEmailSuccess: (_, { codeEmail }) => codeEmail,
            },
        ],
        loadState: [
            'loading' as CodeEmailLoadState,
            {
                loadCodeEmail: (state) => (state === 'loaded' ? state : 'loading'),
                codeEmailLoaded: () => 'loaded',
                codeEmailNotFound: () => 'not-found',
                // A reload that fails keeps showing the email it already has.
                codeEmailLoadFailed: (state) => (state === 'loaded' ? state : 'failed'),
            },
        ],
        saving: [false, { updateCodeEmail: () => true, savesSettled: () => false }],
    }),
    selectors({
        editDisabledReason: [
            (s) => [s.codeEmail],
            // The API answers with the reader's access to this email's own workflow, which can differ from
            // their access to workflows as a whole.
            (codeEmail: CodeEmailApi | null): string | null =>
                getAccessControlDisabledReason(
                    AccessControlResourceType.Workflow,
                    AccessControlLevel.Editor,
                    (codeEmail?.user_access_level ?? undefined) as AccessControlLevel | undefined
                ),
        ],
        breadcrumbs: [
            (s) => [s.codeEmail, (_, props) => props.id],
            (codeEmail: CodeEmailApi | null, id: string): Breadcrumb[] => [
                {
                    key: Scene.Transactional,
                    name: 'Transactional',
                    path: urls.transactional(),
                    iconType: 'transactional',
                },
                {
                    key: [Scene.TransactionalCodeEmail, id],
                    name: codeEmail?.key ?? 'Email',
                    iconType: 'transactional',
                },
            ],
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        loadCodeEmail: async () => {
            try {
                actions.codeEmailLoaded(await transactionalCodeEmailsRetrieve(String(values.currentTeamId), props.id))
            } catch (error) {
                if (error instanceof ApiError && error.status === 404) {
                    actions.codeEmailNotFound()
                } else {
                    actions.codeEmailLoadFailed()
                }
            }
        },
        codeEmailLoaded: ({ codeEmail }) => {
            if (!cache.openedTracked) {
                cache.openedTracked = true
                // pinned: analytics event name
                posthog.capture('code email opened', { has_source_file: !!codeEmail.source_url })
            }
        },
        // Each save replaces the fields it sends, so saves run one at a time and edits made meanwhile go in the
        // next one. Two saves in flight could answer out of order and put back the older values.
        updateCodeEmail: async ({ fields }) => {
            cache.unsavedFields = { ...cache.unsavedFields, ...fields }
            if (cache.saveRunning) {
                return
            }
            cache.saveRunning = true
            try {
                while (cache.unsavedFields) {
                    const sent: PatchedCodeEmailUpdateApi = cache.unsavedFields
                    cache.unsavedFields = null
                    try {
                        const saved = await transactionalCodeEmailsPartialUpdate(
                            String(values.currentTeamId),
                            props.id,
                            sent
                        )
                        actions.updateCodeEmailSuccess({ ...saved, ...cache.unsavedFields }, sent)
                    } catch (error: any) {
                        cache.unsavedFields = null
                        actions.updateCodeEmailFailure(error?.detail || "Couldn't save your change. Try again.")
                    }
                }
            } finally {
                cache.saveRunning = false
                actions.savesSettled()
            }
        },
        updateCodeEmailFailure: ({ error }) => {
            lemonToast.error(error)
            // The page shows edits that were never stored, so the stored email is read back.
            actions.loadCodeEmail()
        },
        showSends: ({ searchParams }) => {
            // The Sends tab reads its filters from the URL, so the drilldown stays on this page.
            router.actions.replace(router.values.location.pathname, searchParams, router.values.hashParams)
        },
    })),
    afterMount(({ actions }) => actions.loadCodeEmail()),
])
