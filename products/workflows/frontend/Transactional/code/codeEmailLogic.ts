export const codeEmailLogic = kea<codeEmailLogicType>([
    props({} as CodeEmailLogicProps),
    key((props) => props.id),
    path((key) => ['products', 'workflows', 'frontend', 'Transactional', 'code', 'codeEmailLogic', key]),
    connect(() => ({
        values: [
            projectLogic,
            ['currentProjectId'],
            featureFlagLogic,
            ['featureFlags'],
            integrationsLogic,
            ['githubIntegrations'],
        ],
    })),
    actions({
        setTab: (tab: CodeEmailTab) => ({ tab }),
        setSourceFormOpen: (open: boolean) => ({ open }),
        linkSourceFile: (sourceUrl: string) => ({ sourceUrl }),
        pickSourceCandidate: (candidate: CodeEmailSourceCandidateApi) => ({ candidate }),
        copyAgentPrompt: true,
    }),
    loaders(({ props, values }) => ({
        // undefined until the first load answers, null when the project has no such email.
        codeEmail: [
            undefined as CodeEmailApi | null | undefined,
            {
                loadCodeEmail: async () => {
                    try {
                        return await transactionalCodeEmailsRetrieve(String(values.currentProjectId), props.id)
                    } catch (error) {
                        if (error instanceof ApiError && error.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
                updateCodeEmail: async (fields: PatchedCodeEmailUpdateApi) =>
                    await transactionalCodeEmailsPartialUpdate(String(values.currentProjectId), props.id, fields),
            },
        ],
        sourceCandidates: [
            null as CodeEmailSourceCandidatesApi | null,
            {
                findSourceCandidates: async () =>
                    await transactionalCodeEmailsSourceCandidatesRetrieve(String(values.currentProjectId), props.id),
            },
        ],
    })),
    reducers({
        tab: ['metrics' as CodeEmailTab, { setTab: (_, { tab }) => tab }],
        sourceFormOpen: [
            false,
            {
                setSourceFormOpen: (_, { open }) => open,
                findSourceCandidates: () => true,
                updateCodeEmailSuccess: () => false,
            },
        ],
        // The open dropdown shows the GitHub search results instead of the paste form.
        sourcePickerOpen: [
            false,
            {
                findSourceCandidates: () => true,
                setSourceFormOpen: () => false,
                updateCodeEmailSuccess: () => false,
            },
        ],
        sourceCandidatesError: [
            null as string | null,
            {
                findSourceCandidates: () => null,
                findSourceCandidatesFailure: (_, { errorObject }) =>
                    errorObject?.detail || "Couldn't search GitHub. Try again in a minute.",
            },
        ],
    }),
    selectors({
        sourceDetectionEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean =>
                !!featureFlags[FEATURE_FLAGS.WORKFLOWS_CODE_EMAIL_SOURCE_DETECTION],
        ],
        canFindInGitHub: [
            (s) => [s.sourceDetectionEnabled, s.githubIntegrations],
            (sourceDetectionEnabled: boolean, githubIntegrations: IntegrationType[]): boolean =>
                sourceDetectionEnabled && githubIntegrations.length > 0,
        ],
        breadcrumbs: [
            (s) => [s.codeEmail, (_, props) => props.id],
            (codeEmail: CodeEmailApi | null | undefined, id: string): Breadcrumb[] => [
                {
                    key: Scene.Transactional,
                    name: 'Transactional',
                    path: urls.transactional(),
                    iconType: 'transactional',
                },
                {
                    key: [Scene.TransactionalCodeEmail, id],
                    name: codeEmail?.key ?? 'Email',
                    iconType: 'transactional',
                },
            ],
        ],
    }),
    listeners(({ actions, values }) => ({
        loadCodeEmailSuccess: ({ codeEmail }) => {
            if (codeEmail) {
                // pinned: analytics event name
                posthog.capture('code email opened', {
                    has_source_file: !!codeEmail.source_url,
                    source_origin: codeEmail.source_url ? codeEmail.source_origin : null,
                })
            }
        },
        linkSourceFile: ({ sourceUrl }) => {
            // pinned: analytics event name
            posthog.capture('code email source file linked', {
                changed: !!values.codeEmail?.source_url,
                host: parseSourceFile(sourceUrl).host,
            })
            actions.updateCodeEmail({ source_url: sourceUrl })
        },
        findSourceCandidatesSuccess: ({ sourceCandidates }) => {
            // pinned: analytics event name
            posthog.capture('code email source searched', {
                candidates: sourceCandidates?.candidates.length ?? 0,
                call_sites: sourceCandidates?.candidates.filter((candidate) => candidate.call_site).length ?? 0,
                complete: sourceCandidates?.complete ?? false,
            })
        },
        findSourceCandidatesFailure: ({ errorObject }) => {
            // pinned: analytics event name
            posthog.capture('code email source search failed', { status: errorObject?.status ?? null })
        },
        pickSourceCandidate: ({ candidate }) => {
            // pinned: analytics event name
            posthog.capture('code email source candidate picked', {
                call_site: candidate.call_site,
                position: values.sourceCandidates?.candidates.indexOf(candidate) ?? -1,
                candidates: values.sourceCandidates?.candidates.length ?? 0,
            })
            actions.updateCodeEmail({ source_url: candidate.url })
        },
        updateCodeEmailFailure: ({ errorObject }) => {
            lemonToast.error(errorObject?.detail || "Couldn't save your change. Try again.")
        },
        copyAgentPrompt: async () => {
            if (values.codeEmail && (await copyToClipboard(agentPrompt(values.codeEmail), 'prompt'))) {
                // pinned: analytics event name
                posthog.capture('code email agent prompt copied', { has_source_file: !!values.codeEmail.source_url })
            }
        },
    })),
    afterMount(({ actions }) => actions.loadCodeEmail()),
])
