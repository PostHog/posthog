import { DEFAULT_LOG_FILTERS, LOG_PAGE_SIZE, logWindow } from './transactionalEmailLogLogic'

export interface TransactionalPushLogFilters {
    search: string
    status: PushSendStatusEnumApi | null
    // The workflow behind the push notification, which the log filters on.
    workflowId: string | null
    dateFrom: string
    dateTo: string | null
    page: number
}

const DEFAULT_PUSH_LOG_FILTERS: TransactionalPushLogFilters = {
    search: '',
    status: null,
    workflowId: null,
    dateFrom: DEFAULT_LOG_FILTERS.dateFrom,
    dateTo: null,
    page: 1,
}

interface PushLogPage {
    results: TransactionalPushLogEntryApi[]
    hasMore: boolean
    // Every page of one listing reads the same window, so sends that arrive later don't shift the offsets.
    dateFrom: string
    dateTo: string
    key: string
}

