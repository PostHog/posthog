/** The push sends in the Log tab. The date range is the one the email log uses, so switching channel keeps it. */
export const transactionalPushLogLogic = kea<transactionalPushLogLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'log', 'transactionalPushLogLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], transactionalEmailLogLogic, ['filters as logFilters']],
        actions: [transactionalEmailLogLogic, ['setFilters as setLogFilters']],
    })),
    actions({
        setFilters: (filters: Partial<TransactionalPushLogFilters>) => ({ filters }),
        setPage: (page: number) => ({ page }),
        refresh: true,
    }),
    reducers({
        pageFailed: [
            false,
            {
                loadPushes: () => false,
                loadPushesSuccess: () => false,
                loadPushesFailure: () => true,
            },
        ],
        filters: [
            DEFAULT_PUSH_LOG_FILTERS as TransactionalPushLogFilters,
            {
                // Any other filter change starts the listing over from its first page.
                setFilters: (state, { filters }) => ({ ...state, page: 1, ...filters }),
                setLogFilters: (state) => ({ ...state, page: 1 }),
                setPage: (state, { page }) => ({ ...state, page }),
                refresh: (state) => ({ ...state, page: 1 }),
            },
        ],
    }),
    loaders(({ values }) => ({
        page: [
            null as PushLogPage | null,
            {
                loadPushes: async ({ fresh }: { fresh?: boolean } = {}, breakpoint) => {
                    await breakpoint(300)
                    const { filters, logFilters, currentProjectId } = values
                    const key = JSON.stringify({
                        ...filters,
                        page: 0,
                        dateFrom: logFilters.dateFrom,
                        dateTo: logFilters.dateTo,
                    })
                    const previous = values.page
                    const { dateFrom, dateTo } =
                        !fresh && previous && previous.key === key ? previous : logWindow(logFilters)
                    if (currentProjectId === null) {
                        return { results: [], hasMore: false, dateFrom, dateTo, key }
                    }
                    const response = await transactionalPushLogList(String(currentProjectId), {
                        search: filters.search.trim() || undefined,
                        status: filters.status ?? undefined,
                        workflow_id: filters.workflowId ?? undefined,
                        date_from: dateFrom,
                        date_to: dateTo,
                        limit: LOG_PAGE_SIZE,
                        offset: (filters.page - 1) * LOG_PAGE_SIZE,
                    })
                    breakpoint()
                    return { results: [...response.results], hasMore: response.has_more, dateFrom, dateTo, key }
                },
            },
        ],
    })),
    selectors({
        pushes: [(s) => [s.page], (page: PushLogPage | null): TransactionalPushLogEntryApi[] => page?.results ?? []],
        isFiltered: [
            (s) => [s.filters],
            (filters: TransactionalPushLogFilters): boolean =>
                !!filters.search.trim() || !!filters.status || !!filters.workflowId,
        ],
        pagination: [
            (s) => [s.page, s.filters],
            (page: PushLogPage | null, filters: TransactionalPushLogFilters): PaginationManual => {
                const seen = (filters.page - 1) * LOG_PAGE_SIZE + (page?.results.length ?? 0)
                return {
                    controlled: true,
                    pageSize: LOG_PAGE_SIZE,
                    currentPage: filters.page,
                    // The log doesn't count every match, so while more pages exist the total reads as "N+".
                    entryCount: page?.hasMore ? seen + 1 : seen,
                    entryCountIsLowerBound: !!page?.hasMore,
                }
            },
        ],
    }),
    listeners(({ actions }) => ({
        setFilters: () => actions.loadPushes(),
        setLogFilters: () => actions.loadPushes(),
        setPage: () => actions.loadPushes(),
        refresh: () => actions.loadPushes({ fresh: true }),
    })),
    afterMount(({ actions }) => {
        actions.loadPushes()
    }),
])
