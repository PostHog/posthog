/**
 * The push sends in the Log tab. The dates live in the URL params the email log uses, so switching channel keeps them.
 */
export const transactionalPushLogLogic = kea<transactionalPushLogLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'log', 'transactionalPushLogLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
    })),
    actions({
        setFilters: (filters: Partial<TransactionalPushLogFilters>) => ({ filters }),
        setDatesFromUrl: (dates: Pick<TransactionalPushLogFilters, 'dateFrom' | 'dateTo'>) => ({ dates }),
        setPage: (page: number) => ({ page }),
        refresh: true,
    }),
    reducers({
        pageFailed: [
            false,
            {
                loadPushes: () => false,
                loadPushesSuccess: () => false,
                loadPushesFailure: () => true,
            },
        ],
        filters: [
            DEFAULT_PUSH_LOG_FILTERS as TransactionalPushLogFilters,
            {
                // Any other filter change starts the listing over from its first page.
                setFilters: (state, { filters }) => ({ ...state, page: 1, ...filters }),
                setDatesFromUrl: (state, { dates }) => ({ ...state, page: 1, ...dates }),
                setPage: (state, { page }) => ({ ...state, page }),
                refresh: (state) => ({ ...state, page: 1 }),
            },
        ],
    }),
    loaders(({ values }) => ({
        page: [
            null as PushLogPage | null,
            {
                loadPushes: async ({ fresh }: { fresh?: boolean } = {}, breakpoint) => {
                    await breakpoint(300)
                    const { filters, currentTeamIdStrict } = values
                    const key = JSON.stringify({ ...filters, page: 0 })
                    const previous = values.page
                    const { dateFrom, dateTo } =
                        !fresh && previous && previous.key === key ? previous : logWindow(filters)
                    if (!currentTeamIdStrict) {
                        return { results: [], hasMore: false, dateFrom, dateTo, key }
                    }
                    const response = await transactionalPushLogList(String(currentTeamIdStrict), {
                        search: filters.search.trim() || undefined,
                        status: filters.status ?? undefined,
                        workflow_id: filters.workflowId ?? undefined,
                        date_from: dateFrom,
                        date_to: dateTo,
                        limit: LOG_PAGE_SIZE,
                        offset: (filters.page - 1) * LOG_PAGE_SIZE,
                    })
                    breakpoint()
                    return { results: [...response.results], hasMore: response.has_more, dateFrom, dateTo, key }
                },
            },
        ],
    })),
    selectors({
        pushes: [(s) => [s.page], (page: PushLogPage | null): TransactionalPushLogEntryApi[] => page?.results ?? []],
        isFiltered: [
            (s) => [s.filters],
            (filters: TransactionalPushLogFilters): boolean =>
                !!filters.search.trim() || !!filters.status || !!filters.workflowId,
        ],
        pagination: [
            (s) => [s.page, s.filters],
            (page: PushLogPage | null, filters: TransactionalPushLogFilters): PaginationManual => {
                const seen = (filters.page - 1) * LOG_PAGE_SIZE + (page?.results.length ?? 0)
                return {
                    controlled: true,
                    pageSize: LOG_PAGE_SIZE,
                    currentPage: filters.page,
                    // The log doesn't count every match, so while more pages exist the total reads as "N+".
                    entryCount: page?.hasMore ? seen + 1 : seen,
                    entryCountIsLowerBound: !!page?.hasMore,
                }
            },
        ],
    }),
    listeners(({ actions }) => ({
        setFilters: () => actions.loadPushes(),
        setDatesFromUrl: () => actions.loadPushes(),
        setPage: () => actions.loadPushes(),
        refresh: () => actions.loadPushes({ fresh: true }),
    })),
    actionToUrl(({ values }) => ({
        setFilters: ({ filters }) => {
            if (!('dateFrom' in filters || 'dateTo' in filters)) {
                return undefined
            }
            const { dateFrom, dateTo } = values.filters
            // The page in the URL is the email log's, which would point into another date range.
            const { date_from: _from, date_to: _to, page: _page, ...searchParams } = router.values.searchParams
            if (dateFrom !== DEFAULT_LOG_FILTERS.dateFrom) {
                searchParams.date_from = dateFrom
            }
            if (dateTo) {
                searchParams.date_to = dateTo
            }
            return [router.values.location.pathname, searchParams, router.values.hashParams, { replace: true }]
        },
    })),
    urlToAction(({ actions, values }) => ({
        '/transactional/log': (_, searchParams) => {
            const dateFrom = searchParams.date_from ? String(searchParams.date_from) : DEFAULT_LOG_FILTERS.dateFrom
            const dateTo = searchParams.date_to ? String(searchParams.date_to) : null
            if (dateFrom !== values.filters.dateFrom || dateTo !== values.filters.dateTo) {
                actions.setDatesFromUrl({ dateFrom, dateTo })
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadPushes()
    }),
])
