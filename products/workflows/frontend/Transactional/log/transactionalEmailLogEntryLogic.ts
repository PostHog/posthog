export const transactionalEmailLogEntryLogic = kea<transactionalEmailLogEntryLogicType>([
    props({} as TransactionalEmailLogEntryLogicProps),
    key((props) => props.messageId),
    path((key) => [
        'products',
        'workflows',
        'frontend',
        'Transactional',
        'log',
        'transactionalEmailLogEntryLogic',
        key,
    ]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']],
        actions: [featureFlagLogic, ['setFeatureFlags']],
    })),
    actions({
        showAllBefore: true,
        showAllAfter: true,
    }),
    reducers({
        beforeExpanded: [false, { showAllBefore: () => true }],
        afterExpanded: [false, { showAllAfter: () => true }],
        personFailed: [
            false,
            {
                loadPerson: () => false,
                loadPersonSuccess: () => false,
                loadPersonFailure: () => true,
            },
        ],
        activityFailed: [
            false,
            {
                loadActivity: () => false,
                loadActivitySuccess: () => false,
                loadActivityFailure: () => true,
            },
        ],
        activityDenied: [
            false,
            {
                loadActivity: () => false,
                loadActivitySuccess: () => false,
                loadActivityFailure: (_, { errorObject }) => errorObject?.status === 403,
            },
        ],
        otherEmailsFailed: [
            false,
            {
                loadOtherEmails: () => false,
                loadOtherEmailsSuccess: () => false,
                loadOtherEmailsFailure: () => true,
            },
        ],
        emailFailed: [
            false,
            {
                loadEmail: () => false,
                loadEmailSuccess: () => false,
                loadEmailFailure: () => true,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        // undefined until the first load answers, null when the project has no send with this ID.
        email: [
            undefined as TransactionalEmailLogDetailApi | null | undefined,
            {
                loadEmail: async () => {
                    if (values.currentProjectId === null) {
                        return null
                    }
                    try {
                        return await transactionalEmailLogRetrieve(String(values.currentProjectId), props.messageId)
                    } catch (error: any) {
                        if (error?.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
            },
        ],
        // undefined until the lookup answers, null when no person has the send's distinct ID.
        person: [
            undefined as ActivityPerson | null | undefined,
            {
                loadPerson: async (distinctId: string) => await fetchActivityPerson(distinctId),
            },
        ],
        otherEmails: [
            [] as TransactionalEmailLogEntryApi[],
            {
                loadOtherEmails: async (email: TransactionalEmailLogDetailApi) =>
                    values.currentProjectId === null
                        ? []
                        : await fetchOtherEmails(
                              values.currentProjectId,
                              email.recipient,
                              email.message_id,
                              email.created_at
                          ),
            },
        ],
        activity: [
            null as SendActivity | null,
            {
                loadActivity: async () =>
                    values.currentProjectId === null
                        ? null
                        : await fetchSendActivity(values.currentProjectId, props.messageId),
            },
        ],
    })),
    selectors({
        emailPageUrl: [
            (s) => [s.email, s.featureFlags, router.selectors.searchParams],
            (
                email: TransactionalEmailLogDetailApi | null | undefined,
                featureFlags: FeatureFlagsSet,
                searchParams: Record<string, unknown>
            ): string | null =>
                featureFlags[FEATURE_FLAGS.WORKFLOWS_EMAIL_SEND_LINKS]
                    ? transactionalEmailSendsUrl(email, searchParams)
                    : templatePageUrl(email?.template_id),
        ],
        impactUrl: [
            (s) => [s.email, s.featureFlags],
            (
                email: TransactionalEmailLogDetailApi | null | undefined,
                featureFlags: FeatureFlagsSet
            ): string | null => {
                const url = transactionalEmailUrl(email)
                return url && featureFlags[FEATURE_FLAGS.WORKFLOWS_EMAIL_IMPACT]
                    ? combineUrl(url, { tab: 'impact' }).url
                    : null
            },
        ],
        outcomesShown: [
            (s) => [s.email, s.featureFlags],
            (email: TransactionalEmailLogDetailApi | null | undefined, featureFlags: FeatureFlagsSet): boolean =>
                !!email && !!featureFlags[FEATURE_FLAGS.WORKFLOWS_EMAIL_SEND_TIMELINE] && emailWentOut(email),
        ],
        outcomeRows: [
            (s) => [s.email, s.activity],
            (email: TransactionalEmailLogDetailApi | null | undefined, activity: SendActivity | null) => {
                if (!email) {
                    return null
                }
                if (activity) {
                    return emailOutcomeRows(email, activity.clicks, activity.emailEvents)
                }
                return emailClicked(email) ? null : emailOutcomeRows(email, [], [])
            },
        ],
        breadcrumbs: [
            (_, p) => [p.messageId],
            (messageId: string): Breadcrumb[] => [
                {
                    key: Scene.Transactional,
                    name: 'Transactional',
                    path: urls.transactional(),
                    iconType: 'transactional',
                },
                { key: 'log', name: 'Log', path: urls.transactionalLog(), iconType: 'transactional' },
                {
                    key: [Scene.TransactionalEmailLogEntry, messageId],
                    // The page title comes from this name, and analytics record the page title.
                    name: 'Email',
                    iconType: 'transactional',
                },
            ],
        ],
    }),
    listeners(({ actions, values }) => {
        const loadClicksWithoutPerson = (): void => {
            const { email } = values
            if (
                email &&
                emailClicked(email) &&
                !email.distinct_id &&
                values.featureFlags[FEATURE_FLAGS.WORKFLOWS_EMAIL_SEND_TIMELINE] &&
                !values.activity &&
                !values.activityLoading
            ) {
                actions.loadActivity()
            }
        }
        return {
            setFeatureFlags: loadClicksWithoutPerson,
            loadEmailSuccess: ({ email }) => {
                if (email?.distinct_id) {
                    actions.loadPerson(email.distinct_id)
                    actions.loadActivity()
                } else {
                    loadClicksWithoutPerson()
                }
                if (email?.recipient) {
                    actions.loadOtherEmails(email)
                }
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('transactional email log entry viewed', {
                    found: !!email,
                    status: email?.status,
                    opened: email?.opened,
                    clicked: email?.clicked,
                })
            },
        }
    }),
    afterMount(({ actions }) => actions.loadEmail()),
])
