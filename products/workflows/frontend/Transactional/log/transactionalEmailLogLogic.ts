export const LOG_PAGE_SIZE = 50
/** The log keeps sends for 30 days, so a wider range can't find more. */
export const LOG_RETENTION_DAYS = 30

// pinned: URL search params of the Log tab and of an email's Sends tab - renaming breaks shared links
const URL_PARAMS = ['search', 'status', 'reason', 'email', 'date_from', 'date_to', 'page'] as const
const EMAIL_PAGE_ROUTES = [
    '/transactional/code-emails/:id',
    '/transactional/library/templates/:id',
    '/workflows/library/templates/:id',
    '/broadcasts/library/templates/:id',
]
const SEND_FILTER_VALUES: Record<string, (filters: TransactionalEmailLogFilters) => string | null> = {
    status: (filters) => filters.status,
    reason: (filters) => filters.reason,
    date_from: (filters) => (filters.dateFrom !== DEFAULT_LOG_FILTERS.dateFrom ? filters.dateFrom : null),
    date_to: (filters) => filters.dateTo,
}
export const SEND_FILTER_PARAMS = Object.keys(SEND_FILTER_VALUES)

export interface TransactionalEmailLogLogicProps {
    workflowId?: string
}

export interface TransactionalEmailLogFilters {
    search: string
    status: EmailDeliveryStatusEnumApi | null
    reason: string | null
    // The workflow behind the transactional email, which the log filters on.
    workflowId: string | null
    dateFrom: string
    dateTo: string | null
    page: number
}

export const DEFAULT_LOG_FILTERS: TransactionalEmailLogFilters = {
    search: '',
    status: null,
    reason: null,
    workflowId: null,
    dateFrom: '-7d',
    dateTo: null,
    page: 1,
}

interface LogPage {
    results: TransactionalEmailLogEntryApi[]
    hasMore: boolean
    // Every page of one listing reads the same window, so sends that arrive later don't shift the offsets.
    dateFrom: string
    dateTo: string
    filters: TransactionalEmailLogFilters
}

