export type transactionalEmailLogLogicType = MakeLogicType<
    transactionalEmailLogLogicValues,
    transactionalEmailLogLogicActions,
    Record<string, any>,
    transactionalEmailLogLogicMeta
>

export const transactionalEmailLogLogic = kea<transactionalEmailLogLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'log', 'transactionalEmailLogLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        setFilters: (filters: Partial<TransactionalEmailLogFilters>) => ({ filters }),
        setFiltersFromUrl: (filters: TransactionalEmailLogFilters) => ({ filters }),
        setPage: (page: number) => ({ page }),
        refresh: true,
    }),
    reducers({
        pageFailed: [
            false,
            {
                loadEmails: () => false,
                loadEmailsSuccess: () => false,
                loadEmailsFailure: () => true,
            },
        ],
        filters: [
            DEFAULT_LOG_FILTERS as TransactionalEmailLogFilters,
            {
                // Any other filter change starts the listing over from its first page.
                setFilters: (state, { filters }) => ({ ...state, page: 1, ...filters }),
                setFiltersFromUrl: (_, { filters }) => filters,
                setPage: (state, { page }) => ({ ...state, page }),
                refresh: (state) => ({ ...state, page: 1 }),
            },
        ],
    }),
    loaders(({ values }) => ({
        page: [
            null as LogPage | null,
            {
                loadEmails: async ({ fresh }: { fresh?: boolean } = {}, breakpoint) => {
                    await breakpoint(300)
                    const filters = values.filters
                    const previous = values.page
                    const window =
                        !fresh && previous && sameListing(previous.filters, filters)
                            ? { dateFrom: previous.dateFrom, dateTo: previous.dateTo }
                            : logWindow(filters)
                    const results = await fetchPage(values.currentProjectId, filters, window)
                    breakpoint()
                    return results
                },
            },
        ],
    })),
    selectors({
        emails: [(s) => [s.page], (page: LogPage | null): TransactionalEmailLogEntryApi[] => page?.results ?? []],
        isFiltered: [
            (s) => [s.filters],
            (filters: TransactionalEmailLogFilters): boolean =>
                !!filters.search.trim() || !!filters.status || !!filters.workflowId,
        ],
        pagination: [
            (s) => [s.page, s.filters],
            (page: LogPage | null, filters: TransactionalEmailLogFilters): PaginationManual => {
                const seen = (filters.page - 1) * LOG_PAGE_SIZE + (page?.results.length ?? 0)
                return {
                    controlled: true,
                    pageSize: LOG_PAGE_SIZE,
                    currentPage: filters.page,
                    // The log doesn't count every match, so while more pages exist the total reads as "N+".
                    entryCount: page?.hasMore ? seen + 1 : seen,
                    entryCountIsLowerBound: !!page?.hasMore,
                }
            },
        ],
    }),
    listeners(({ actions }) => ({
        setFilters: () => actions.loadEmails(),
        setFiltersFromUrl: () => actions.loadEmails(),
        setPage: () => actions.loadEmails(),
        refresh: () => actions.loadEmails({ fresh: true }),
    })),
    // A search can be a recipient's address, and pageviews record the URL, so the search stays out of it.
    actionToUrl(({ values }) => {
        const toUrl = (): [string, Record<string, any>, Record<string, any>, { replace: boolean }] => {
            const { status, workflowId, dateFrom, dateTo, page } = values.filters
            const searchParams: Record<string, any> = { ...router.values.searchParams }
            URL_PARAMS.forEach((key) => delete searchParams[key])
            if (status) {
                searchParams.status = status
            }
            if (workflowId) {
                searchParams.email = workflowId
            }
            if (dateFrom !== DEFAULT_LOG_FILTERS.dateFrom) {
                searchParams.date_from = dateFrom
            }
            if (dateTo) {
                searchParams.date_to = dateTo
            }
            if (page > 1) {
                searchParams.page = page
            }
            return [router.values.location.pathname, searchParams, router.values.hashParams, { replace: true }]
        }
        return { setFilters: toUrl, setPage: toUrl, refresh: toUrl }
    }),
    urlToAction(({ actions, values }) => ({
        '/transactional/log': (_, searchParams) => {
            const page = Number(searchParams.page)
            const filters: TransactionalEmailLogFilters = {
                search: values.filters.search,
                status: (searchParams.status as EmailDeliveryStatusEnumApi | undefined) ?? null,
                workflowId: searchParams.email ? String(searchParams.email) : null,
                dateFrom: searchParams.date_from ? String(searchParams.date_from) : DEFAULT_LOG_FILTERS.dateFrom,
                dateTo: searchParams.date_to ? String(searchParams.date_to) : null,
                page: Number.isInteger(page) && page > 1 ? page : 1,
            }
            if (values.page === null || JSON.stringify(filters) !== JSON.stringify(values.filters)) {
                actions.setFiltersFromUrl(filters)
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.page === null) {
            actions.loadEmails()
        }
    }),
])

/** The window a date filter covers, clamped to what the log keeps. */
export function logWindow(filters: Pick<TransactionalEmailLogFilters, 'dateFrom' | 'dateTo'>): {
    dateFrom: string
    dateTo: string
} {
    const now = dayjs()
    const oldest = now.subtract(LOG_RETENTION_DAYS, 'day')
    const from = dateStringToDayJs(filters.dateFrom) ?? now.subtract(7, 'day')
    const to = (filters.dateTo ? dateStringToDayJs(filters.dateTo) : null) ?? now
    return {
        dateFrom: (from.isBefore(oldest) ? oldest : from).toISOString(),
        dateTo: (to.isAfter(now) ? now : to).toISOString(),
    }
}

function sameListing(a: TransactionalEmailLogFilters, b: TransactionalEmailLogFilters): boolean {
    return JSON.stringify({ ...a, page: 0 }) === JSON.stringify({ ...b, page: 0 })
}

async function fetchPage(
    projectId: number | null,
    filters: TransactionalEmailLogFilters,
    { dateFrom, dateTo }: { dateFrom: string; dateTo: string }
): Promise<LogPage> {
    if (projectId === null) {
        return { results: [], hasMore: false, dateFrom, dateTo, filters }
    }
    const response = await transactionalEmailLogList(String(projectId), {
        search: filters.search.trim() || undefined,
        status: filters.status ?? undefined,
        workflow_id: filters.workflowId ?? undefined,
        date_from: dateFrom,
        date_to: dateTo,
        limit: LOG_PAGE_SIZE,
        offset: (filters.page - 1) * LOG_PAGE_SIZE,
    })
    return { results: [...response.results], hasMore: response.has_more, dateFrom, dateTo, filters }
}
