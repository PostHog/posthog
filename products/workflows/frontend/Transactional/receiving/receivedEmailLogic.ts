import {
    MakeLogicType,
    actions,
    afterMount,
    beforeUnmount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
    selectors,
} from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { projectLogic } from 'scenes/projectLogic'
import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { Breadcrumb } from '~/types'

import { receivedEmailsRetrieve } from 'products/workflows/frontend/generated/api'
import type { ReceivedEmailDetailApi } from 'products/workflows/frontend/generated/api.schemas'

export interface ReceivedEmailLogicProps {
    id: string
}

export type ReceivedEmailBodyTab = 'preview' | 'text' | 'reply' | 'html' | 'raw'

const LINK_REFRESH_MARGIN_MS = 60 * 1000

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface receivedEmailLogicValues {
    currentProjectId: number | null // projectLogic
    bodyTab: ReceivedEmailBodyTab
    breadcrumbs: Breadcrumb[]
    chosenBodyTab: ReceivedEmailBodyTab | null
    email: ReceivedEmailDetailApi | null | undefined
    emailFailed: boolean
    emailLoading: boolean
    remoteImagesLoaded: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface receivedEmailLogicActions {
    loadEmail: () => any
    loadEmailFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadEmailSuccess: (
        email: ReceivedEmailDetailApi | null,
        payload?: any
    ) => {
        email: ReceivedEmailDetailApi | null
        payload?: any
    }
    loadRemoteImages: () => {
        value: true
    }
    setBodyTab: (tab: ReceivedEmailBodyTab) => {
        tab: ReceivedEmailBodyTab
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface receivedEmailLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        bodyTab: (
            chosenBodyTab: ReceivedEmailBodyTab | null,
            email: ReceivedEmailDetailApi | null | undefined
        ) => ReceivedEmailBodyTab
        breadcrumbs: (arg: any) => Breadcrumb[]
    }
}

export type receivedEmailLogicType = MakeLogicType<
    receivedEmailLogicValues,
    receivedEmailLogicActions,
    ReceivedEmailLogicProps,
    receivedEmailLogicMeta
>

export const receivedEmailLogic = kea<receivedEmailLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'receiving', 'receivedEmailLogic']),
    props({} as ReceivedEmailLogicProps),
    key(({ id }) => id),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        setBodyTab: (tab: ReceivedEmailBodyTab) => ({ tab }),
        loadRemoteImages: true,
    }),
    reducers({
        chosenBodyTab: [null as ReceivedEmailBodyTab | null, { setBodyTab: (_, { tab }) => tab }],
        remoteImagesLoaded: [false, { loadRemoteImages: () => true }],
        emailFailed: [
            false,
            {
                loadEmail: () => false,
                loadEmailSuccess: () => false,
                loadEmailFailure: () => true,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        email: [
            undefined as ReceivedEmailDetailApi | null | undefined,
            {
                loadEmail: async () => {
                    try {
                        return await receivedEmailsRetrieve(String(values.currentProjectId), props.id)
                    } catch (error: any) {
                        if (error?.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
            },
        ],
    })),
    selectors({
        bodyTab: [
            (s) => [s.chosenBodyTab, s.email],
            (chosen: ReceivedEmailBodyTab | null, email: ReceivedEmailDetailApi | null | undefined) =>
                chosen ?? (email && !email.html ? 'text' : 'preview'),
        ],
        breadcrumbs: [
            () => [(_, props) => props.id],
            // The last breadcrumb becomes the document title, which analytics records, so a subject can't go in it.
            (id: string): Breadcrumb[] => [
                { key: Scene.Transactional, name: 'Received email', path: urls.transactionalReceived() },
                { key: [Scene.TransactionalReceivedEmail, id], name: 'Email' },
            ],
        ],
    }),
    listeners(({ actions, cache }) => ({
        loadRemoteImages: () => {
            posthog.capture('received email remote images loaded')
        },
        loadEmailSuccess: ({ email }) => {
            if (!email) {
                return
            }
            if (!cache.openCaptured) {
                cache.openCaptured = true
                posthog.capture('received email opened', {
                    status: email.status,
                    has_person: !!email.person,
                    has_original_send: !!email.original_send,
                    attachment_count: email.attachment_count,
                })
            }
            // Download links stop working at this time, so someone who leaves the page open gets fresh ones.
            clearTimeout(cache.linkRefresh)
            cache.linkRefresh = setTimeout(
                () => actions.loadEmail(),
                Math.max(new Date(email.raw.expires_at).getTime() - Date.now() - LINK_REFRESH_MARGIN_MS, 0)
            )
        },
    })),
    afterMount(({ actions }) => {
        actions.loadEmail()
    }),
    beforeUnmount(({ cache }) => {
        clearTimeout(cache.linkRefresh)
    }),
])
