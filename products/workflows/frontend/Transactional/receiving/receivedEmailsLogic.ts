export interface receivedEmailsLogicActions {
    loadEmails: (_: void) => void
    loadEmailsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadEmailsSuccess: (
        page: ReceivedEmailListApi,
        payload?: void
    ) => {
        page: ReceivedEmailListApi
        payload?: void
    }
    refresh: () => {
        value: true
    }
    setFilters: (filters: Partial<ReceivedEmailFilters>) => {
        filters: Partial<ReceivedEmailFilters>
    }
    setFiltersFromUrl: (filters: ReceivedEmailFilters) => {
        filters: ReceivedEmailFilters
    }
    setPage: (page: number) => {
        page: number
    }
}

