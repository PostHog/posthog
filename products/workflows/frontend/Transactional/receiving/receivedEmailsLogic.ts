export type receivedEmailsLogicType = MakeLogicType<
    receivedEmailsLogicValues,
    receivedEmailsLogicActions,
    Record<string, any>,
    receivedEmailsLogicMeta
>

export const receivedEmailsLogic = kea<receivedEmailsLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'receiving', 'receivedEmailsLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        setFilters: (filters: Partial<ReceivedEmailFilters>) => ({ filters }),
        setFiltersFromUrl: (filters: ReceivedEmailFilters) => ({ filters }),
        setPage: (page: number) => ({ page }),
        refresh: true,
    }),
    reducers({
        filters: [
            DEFAULT_RECEIVED_FILTERS as ReceivedEmailFilters,
            {
                setFilters: (state, { filters }) => ({ ...state, page: 1, ...filters }),
                setFiltersFromUrl: (_, { filters }) => filters,
                setPage: (state, { page }) => ({ ...state, page }),
            },
        ],
        pageFailed: [
            false,
            {
                loadEmails: () => false,
                loadEmailsSuccess: () => false,
                loadEmailsFailure: () => true,
            },
        ],
    }),
    loaders(({ values }) => ({
        page: [
            null as ReceivedEmailListApi | null,
            {
                loadEmails: async (_: void, breakpoint) => {
                    await breakpoint(200)
                    const { search, status, dateFrom, dateTo, page } = values.filters
                    const results = await receivedEmailsList(String(values.currentProjectId), {
                        search: search.trim() || undefined,
                        status: status === 'all' ? undefined : status,
                        date_from: dateParam(dateFrom),
                        date_to: dateTo ? dateParam(dateTo) : undefined,
                        limit: RECEIVED_PAGE_SIZE,
                        offset: (page - 1) * RECEIVED_PAGE_SIZE,
                    })
                    breakpoint()
                    return results
                },
            },
        ],
    })),
    selectors({
        emails: [(s) => [s.page], (page: ReceivedEmailListApi | null): ReceivedEmailApi[] => page?.results ?? []],
        filteredCount: [(s) => [s.page], (page: ReceivedEmailListApi | null): number => page?.filtered_count ?? 0],
        isFiltered: [
            (s) => [s.filters],
            (filters: ReceivedEmailFilters): boolean =>
                !!filters.search.trim() || filters.status !== DEFAULT_RECEIVED_FILTERS.status,
        ],
        // Nothing matched and nothing narrowed the list, so this project is still waiting for its first email.
        isWaitingForMail: [
            (s) => [s.page, s.emails, s.isFiltered, s.filteredCount, s.filters],
            (
                page: ReceivedEmailListApi | null,
                emails: ReceivedEmailApi[],
                isFiltered: boolean,
                filteredCount: number,
                filters: ReceivedEmailFilters
            ): boolean =>
                page !== null &&
                emails.length === 0 &&
                !isFiltered &&
                filteredCount === 0 &&
                filters.page === 1 &&
                filters.dateFrom === DEFAULT_RECEIVED_FILTERS.dateFrom &&
                !filters.dateTo,
        ],
        pagination: [
            (s) => [s.page, s.filters],
            (page: ReceivedEmailListApi | null, filters: ReceivedEmailFilters): PaginationManual => {
                const seen = (filters.page - 1) * RECEIVED_PAGE_SIZE + (page?.results.length ?? 0)
                return {
                    controlled: true,
                    pageSize: RECEIVED_PAGE_SIZE,
                    currentPage: filters.page,
                    entryCount: page?.has_more ? seen + 1 : seen,
                    entryCountIsLowerBound: !!page?.has_more,
                }
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setFilters: () => actions.loadEmails(),
        setFiltersFromUrl: () => actions.loadEmails(),
        setPage: () => actions.loadEmails(),
        refresh: () => actions.loadEmails(),
        loadEmailsSuccess: () => {
            clearTimeout(cache.waitingPoll)
            if (values.isWaitingForMail) {
                cache.waitingPoll = setTimeout(() => actions.loadEmails(), WAITING_POLL_MS)
            }
        },
    })),
    // A search can be someone's address, and pageviews record the URL, so the search stays out of it.
    actionToUrl(({ values }) => {
        const toUrl = (): [string, Record<string, any>, Record<string, any>, { replace: boolean }] => {
            const { status, dateFrom, dateTo, page } = values.filters
            const params: Record<string, any> = {}
            if (status !== DEFAULT_RECEIVED_FILTERS.status) {
                params.status = status
            }
            if (dateFrom !== DEFAULT_RECEIVED_FILTERS.dateFrom) {
                params.date_from = dateFrom
            }
            if (dateTo) {
                params.date_to = dateTo
            }
            if (page > 1) {
                params.page = page
            }
            return [router.values.location.pathname, params, router.values.hashParams, { replace: true }]
        }
        return { setFilters: toUrl, setPage: toUrl }
    }),
    urlToAction(({ actions, values }) => ({
        '/transactional/received': (_, searchParams) => {
            const page = Number(searchParams.page)
            const filters: ReceivedEmailFilters = {
                search: values.filters.search,
                status: (searchParams.status as ReceivedStatusFilter | undefined) ?? DEFAULT_RECEIVED_FILTERS.status,
                dateFrom: searchParams.date_from ? String(searchParams.date_from) : DEFAULT_RECEIVED_FILTERS.dateFrom,
                dateTo: searchParams.date_to ? String(searchParams.date_to) : null,
                page: Number.isInteger(page) && page > 1 ? page : 1,
            }
            if (values.page === null || JSON.stringify(filters) !== JSON.stringify(values.filters)) {
                actions.setFiltersFromUrl(filters)
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.page === null) {
            actions.loadEmails()
        }
    }),
    beforeUnmount(({ cache }) => {
        clearTimeout(cache.waitingPoll)
    }),
])
