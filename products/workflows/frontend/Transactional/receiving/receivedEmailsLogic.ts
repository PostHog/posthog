import {
    MakeLogicType,
    actions,
    afterMount,
    beforeUnmount,
    connect,
    kea,
    listeners,
    path,
    reducers,
    selectors,
} from 'kea'
import { loaders } from 'kea-loaders'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { dayjs } from 'lib/dayjs'
import { PaginationManual } from 'lib/lemon-ui/PaginationControl'
import { dateStringToDayJs } from 'lib/utils/dateFilters'
import { projectLogic } from 'scenes/projectLogic'

import { receivedEmailsList } from 'products/workflows/frontend/generated/api'
import type {
    ReceivedEmailApi,
    ReceivedEmailListApi,
    ReceivedEmailStatusEnumApi,
} from 'products/workflows/frontend/generated/api.schemas'

export const RECEIVED_PAGE_SIZE = 50
export const RECEIVED_RETENTION_DAYS = 30
const WAITING_POLL_MS = 5000

export type ReceivedStatusFilter = ReceivedEmailStatusEnumApi | 'all'

export interface ReceivedEmailFilters {
    search: string
    status: ReceivedStatusFilter
    dateFrom: string
    dateTo: string | null
    page: number
}

export const DEFAULT_RECEIVED_FILTERS: ReceivedEmailFilters = {
    search: '',
    status: 'received',
    dateFrom: '-7d',
    dateTo: null,
    page: 1,
}

function dateParam(value: string): string | undefined {
    return dateStringToDayJs(value)?.toISOString() ?? (dayjs(value).isValid() ? dayjs(value).toISOString() : undefined)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface receivedEmailsLogicValues {
    currentProjectId: number | null // projectLogic
    emails: ReceivedEmailApi[]
    filteredCount: number
    filters: ReceivedEmailFilters
    isFiltered: boolean
    isWaitingForMail: boolean
    page: ReceivedEmailListApi | null
    pageFailed: boolean
    pageLoading: boolean
    pagination: PaginationManual
}

