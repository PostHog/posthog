export const inboundEmailDomainsLogic = kea<inboundEmailDomainsLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'receiving', 'inboundEmailDomainsLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        setStep: (step: DomainModalStep) => ({ step }),
        setHostname: (hostname: string) => ({ hostname }),
        setMoveMailConfirmed: (confirmed: boolean) => ({ confirmed }),
        setFormError: (error: string | null) => ({ error }),
        openDomains: true,
        startAddingDomain: true,
        rotateAddress: true,
        removeDomain: (domain: InboundDomainApi) => ({ domain }),
        addressCopied: true,
    }),
    reducers({
        step: [
            'closed' as DomainModalStep,
            {
                setStep: (_, { step }) => step,
                openDomains: () => 'list',
                startAddingDomain: () => 'form',
            },
        ],
        hostname: ['', { setHostname: (_, { hostname }) => hostname, startAddingDomain: () => '' }],
        moveMailConfirmed: [
            false,
            {
                setMoveMailConfirmed: (_, { confirmed }) => confirmed,
                setHostname: () => false,
                startAddingDomain: () => false,
            },
        ],
        formError: [
            null as string | null,
            {
                setFormError: (_, { error }) => error,
                setHostname: () => null,
                startAddingDomain: () => null,
            },
        ],
    }),
    loaders(({ values, actions }) => ({
        overview: [
            null as InboundDomainsOverviewApi | null,
            {
                loadOverview: async () => await inboundEmailDomainsList(String(values.currentProjectId)),
            },
        ],
        checks: [
            {} as Record<string, InboundDomainCheckApi>,
            {
                checkDomain: async ({ id }: { id: string }) => {
                    const check = await inboundEmailDomainsVerifyCreate(String(values.currentProjectId), id)
                    if (check.state === 'active') {
                        if (values.checks[id]?.state !== 'active') {
                            posthog.capture('inbound email domain verified')
                        }
                        // The polling stops only once the overview says active, so a failed refresh gets another go.
                        if (values.overview?.results.find((domain) => domain.id === id)?.status !== 'active') {
                            actions.loadOverview()
                        }
                    }
                    return { ...values.checks, [id]: check }
                },
            },
        ],
        preflight: [
            null as InboundDomainPreflightApi | null,
            {
                runPreflight: async () => {
                    try {
                        const preflight = await inboundEmailDomainsPreflight(String(values.currentProjectId), {
                            domain: values.hostname,
                        })
                        if (!preflight.eligible) {
                            actions.setFormError(preflight.reason)
                        } else if (preflight.existing_mx.length > 0 || preflight.whole_domain) {
                            actions.setStep('confirm')
                        } else {
                            actions.addDomain()
                        }
                        return preflight
                    } catch (error: any) {
                        actions.setFormError(errorDetail(error))
                        return null
                    }
                },
            },
        ],
        addedDomain: [
            null as InboundDomainCheckApi | null,
            {
                addDomain: async () => {
                    try {
                        const check = await inboundEmailDomainsCreate(String(values.currentProjectId), {
                            domain: values.hostname,
                            confirm_move_mail: values.moveMailConfirmed,
                        })
                        posthog.capture('inbound email domain added', {
                            whole_domain: values.preflight?.whole_domain ?? false,
                            had_mail_hosts: (values.preflight?.existing_mx.length ?? 0) > 0,
                        })
                        actions.setStep('list')
                        actions.loadOverview()
                        return check
                    } catch (error: any) {
                        actions.setFormError(error?.attr === 'domain' ? errorDetail(error) : errorDetail(error))
                        actions.setStep('form')
                        return null
                    }
                },
            },
        ],
        address: [
            null as InboundDomainApi | null,
            {
                ensureAddress: async () => {
                    const address = await inboundEmailDomainsReceivingAddress(String(values.currentProjectId), {})
                    actions.loadOverview()
                    return address
                },
            },
        ],
    })),
    selectors({
        domains: [
            (s) => [s.overview],
            (overview: InboundDomainsOverviewApi | null): InboundDomainApi[] => overview?.results ?? [],
        ],
        generatedDomain: [
            (s) => [s.domains],
            (domains: InboundDomainApi[]): InboundDomainApi | null =>
                domains.find((domain) => domain.kind === 'generated') ?? null,
        ],
        customDomains: [
            (s) => [s.domains],
            (domains: InboundDomainApi[]): InboundDomainApi[] => domains.filter((domain) => domain.kind === 'custom'),
        ],
        pendingDomains: [
            (s) => [s.customDomains],
            (domains: InboundDomainApi[]): InboundDomainApi[] =>
                domains.filter((domain) => domain.status === 'pending'),
        ],
        limitReachedAt: [
            (s) => [s.domains],
            (domains: InboundDomainApi[]): string | null =>
                domains
                    .map((domain) => domain.daily_limit_reached_at)
                    .filter((at): at is string => !!at)
                    .sort()
                    .pop() ?? null,
        ],
    }),
    listeners(({ actions, values }) => ({
        loadOverviewSuccess: ({ overview }) => {
            if (overview?.generated_addresses_available && !values.generatedDomain && !values.addressLoading) {
                actions.ensureAddress()
            }
        },
        rotateAddress: async () => {
            try {
                await inboundEmailDomainsReceivingAddress(String(values.currentProjectId), { rotate: true })
                posthog.capture('inbound email address rotated')
                actions.loadOverview()
            } catch (error: any) {
                lemonToast.error(errorDetail(error))
            }
        },
        removeDomain: async ({ domain }) => {
            try {
                await inboundEmailDomainsDestroy(String(values.currentProjectId), domain.id)
                posthog.capture('inbound email domain removed')
                actions.loadOverview()
            } catch (error: any) {
                lemonToast.error(errorDetail(error))
            }
        },
        addressCopied: () => {
            posthog.capture('inbound email address copied')
        },
        startAddingDomain: () => {
            posthog.capture('inbound email domain add started')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadOverview()
    }),
])
