export const transactionalEmailMetricsLogic = kea<transactionalEmailMetricsLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'metrics', 'transactionalEmailMetricsLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        setHours: (hours: number) => ({ hours }),
        setResultsQuery: (query: Partial<ResultsQuery>) => ({ query }),
    }),
    reducers({
        resultsFailed: [
            false,
            {
                loadResults: () => false,
                loadResultsSuccess: () => false,
                loadResultsFailure: () => true,
            },
        ],
        statsFailed: [
            false,
            {
                loadTemplateStats: () => false,
                loadDomainStats: () => false,
                loadStatsOverTime: () => false,
                loadTemplateStatsFailure: () => true,
                loadDomainStatsFailure: () => true,
                loadStatsOverTimeFailure: () => true,
            },
        ],
        statsOverTimeFailed: [
            false,
            {
                loadStatsOverTime: () => false,
                loadStatsOverTimeSuccess: () => false,
                loadStatsOverTimeFailure: () => true,
            },
        ],
        hours: [(24 * 7) as number, { setHours: (_, { hours }) => hours }],
        resultsQuery: [
            DEFAULT_RESULTS_QUERY as ResultsQuery,
            { setResultsQuery: (state, { query }) => ({ ...state, ...query }) },
        ],
    }),
    loaders(({ values }) => ({
        templateStats: [
            null as TransactionalEmailStatsRowApi[] | null,
            {
                loadTemplateStats: async (_: void, breakpoint) => {
                    return await latest(fetchStats(values.currentProjectId, 'template', values.hours), breakpoint)
                },
            },
        ],
        domainStats: [
            null as TransactionalEmailStatsRowApi[] | null,
            {
                loadDomainStats: async (_: void, breakpoint) => {
                    return await latest(fetchStats(values.currentProjectId, 'sending_domain', values.hours), breakpoint)
                },
            },
        ],
        statsOverTime: [
            null as TransactionalEmailStatsOverTimeApi | null,
            {
                loadStatsOverTime: async (_: void, breakpoint) => {
                    if (values.currentProjectId === null) {
                        return null
                    }
                    return await latest(
                        transactionalEmailLogStatsOverTimeRetrieve(String(values.currentProjectId), {
                            date_from: dayjs().subtract(values.hours, 'hour').toISOString(),
                        }),
                        breakpoint
                    )
                },
            },
        ],
        results: [
            null as TransactionalEmailResultsApi | null,
            {
                loadResults: async (_: void, breakpoint) => {
                    const { workflowId, event, windowDays, revenueProperty } = values.resultsQuery
                    if (values.currentProjectId === null || !workflowId || !event) {
                        return null
                    }
                    await breakpoint(300)
                    return await latest(
                        transactionalEmailLogResultsRetrieve(String(values.currentProjectId), {
                            workflow_id: workflowId,
                            event,
                            window_days: windowDays,
                            revenue_property: revenueProperty ?? undefined,
                            date_from: dayjs().subtract(values.hours, 'hour').toISOString(),
                        }),
                        breakpoint
                    )
                },
            },
        ],
    })),
    selectors({
        canLoadResults: [
            (s) => [s.resultsQuery],
            (query: ResultsQuery): boolean => !!query.workflowId && !!query.event,
        ],
    }),
    listeners(({ actions, values }) => ({
        setHours: () => {
            actions.loadTemplateStats()
            actions.loadDomainStats()
            actions.loadStatsOverTime()
            if (values.canLoadResults) {
                actions.loadResults()
            }
        },
        setResultsQuery: () => {
            if (values.canLoadResults) {
                actions.loadResults()
            }
        },
        loadResultsSuccess: ({ results }) => {
            if (results) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('transactional email results calculated', {
                    window_days: values.resultsQuery.windowDays,
                    has_revenue_property: !!values.resultsQuery.revenueProperty,
                    recipients: results.recipients,
                    converted: results.converted,
                })
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadTemplateStats()
        actions.loadDomainStats()
        actions.loadStatsOverTime()
    }),
])

async function fetchStats(
    projectId: number | null,
    groupBy: 'template' | 'sending_domain',
    hours: number
): Promise<TransactionalEmailStatsRowApi[]> {
    if (projectId === null) {
        return []
    }
    const response = await transactionalEmailLogStatsRetrieve(String(projectId), {
        group_by: groupBy,
        date_from: dayjs().subtract(hours, 'hour').toISOString(),
    })
    return [...response.results]
}

/** Checks the breakpoint whether the request succeeded or failed, so a superseded failure can't replace newer results. */
async function latest<T>(request: Promise<T>, breakpoint: () => void): Promise<T> {
    try {
        return await request
    } finally {
        breakpoint()
    }
}
