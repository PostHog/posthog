export type smtpSetupLogicType = MakeLogicType<
    smtpSetupLogicValues,
    smtpSetupLogicActions,
    Record<string, any>,
    smtpSetupLogicMeta
>

export const smtpSetupLogic = kea<smtpSetupLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'smtp', 'smtpSetupLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentProjectId'],
            integrationsLogic,
            ['integrations', 'integrationsLoading'],
            userLogic,
            ['user'],
        ],
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        setPassword: (password: string) => ({ password }),
        setFrom: (from: string) => ({ from }),
        setTo: (to: string) => ({ to }),
    }),
    loaders(({ values }) => ({
        setup: [
            null as SmtpSetupApi | null,
            {
                loadSetup: async () => await messagingSmtpSetupRetrieve(String(values.currentProjectId)),
            },
        ],
        // Only the key made on this page is ever known here: the API shows a key's value once.
        createdKey: [
            null as string | null,
            {
                createKey: async () => {
                    const key = await api.projectSecretApiKeys.create({
                        // A project's key labels are unique, and someone may create several here.
                        label: `SMTP ${dayjs().format('YYYY-MM-DD HH:mm:ss')}`,
                        scopes: [SMTP_KEY_SCOPE],
                    })
                    return key.value ?? null
                },
            },
        ],
        testResult: [
            null as SmtpTestResponseApi | null,
            {
                sendTest: async () =>
                    await messagingSmtpTestCreate(String(values.currentProjectId), {
                        password: values.password,
                        from: values.testFrom,
                        to: values.testTo,
                    }),
            },
        ],
    })),
    reducers({
        password: [
            '',
            { setPassword: (_, { password }) => password, createKeySuccess: (_, { createdKey }) => createdKey ?? '' },
        ],
        from: [null as string | null, { setFrom: (_, { from }) => from }],
        to: [null as string | null, { setTo: (_, { to }) => to }],
    }),
    selectors({
        senders: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): IntegrationType[] =>
                (integrations ?? []).filter(
                    (integration) => integration.kind === 'email' && integration.config?.verified
                ),
        ],
        senderAddresses: [
            (s) => [s.senders],
            (senders: IntegrationType[]): string[] =>
                senders.map((sender) => sender.config?.email as string).filter(Boolean),
        ],
        testFrom: [
            (s) => [s.from, s.senderAddresses],
            (from: string | null, senderAddresses: string[]): string => from ?? senderAddresses[0] ?? '',
        ],
        testTo: [(s) => [s.to, s.user], (to: string | null, user: UserType | null): string => to ?? user?.email ?? ''],
        testDisabledReason: [
            (s) => [s.password, s.testFrom, s.testTo],
            (password: string, testFrom: string, testTo: string): string | null =>
                !password
                    ? 'Enter a project secret key, or create one above'
                    : !testFrom
                      ? 'Verify a sending domain first'
                      : !testTo
                        ? 'Enter who should get the test email'
                        : null,
        ],
    }),
    listeners(({ actions }) => ({
        createKeySuccess: () => {
            posthog.capture('smtp key created')
        },
        createKeyFailure: () => {
            lemonToast.error("Couldn't create the key. Try again, or create one in project settings.")
        },
        sendTestSuccess: ({ testResult }) => {
            posthog.capture('smtp test sent', { ok: testResult?.ok })
            actions.loadSetup()
        },
        sendTestFailure: () => {
            lemonToast.error("Couldn't run the test. Check the fields and try again.")
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSetup()
        posthog.capture('smtp setup viewed')
    }),
])
