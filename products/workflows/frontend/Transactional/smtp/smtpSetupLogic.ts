import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { dayjs } from 'lib/dayjs'
import { integrationsLogic } from 'lib/integrations/integrationsLogic'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'
import { userLogic } from 'scenes/userLogic'

import { IntegrationType } from '~/types'

import { messagingSmtpSetupRetrieve, messagingSmtpTestCreate } from 'products/messaging/frontend/generated/api'
import type { SmtpSetupApi, SmtpTestResponseApi } from 'products/messaging/frontend/generated/api.schemas'

import type { UserType } from '../../../../../frontend/src/types'

const SMTP_KEY_SCOPE = 'transactional_email:write'

