export const transactionalEmailPerformanceLogic = kea<transactionalEmailPerformanceLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'performance', 'transactionalEmailPerformanceLogic']),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        setDays: (days: number) => ({ days }),
        setResultsQuery: (query: Partial<ResultsQuery>) => ({ query }),
    }),
    reducers({
        days: [7 as number, { setDays: (_, { days }) => days }],
        resultsQuery: [
            DEFAULT_RESULTS_QUERY as ResultsQuery,
            { setResultsQuery: (state, { query }) => ({ ...state, ...query }) },
        ],
    }),
    loaders(({ values }) => ({
        templateStats: [
            null as TransactionalEmailStatsRowApi[] | null,
            {
                loadTemplateStats: async () => await fetchStats(values.currentProjectId, 'template', values.days),
            },
        ],
        domainStats: [
            null as TransactionalEmailStatsRowApi[] | null,
            {
                loadDomainStats: async () => await fetchStats(values.currentProjectId, 'sending_domain', values.days),
            },
        ],
        results: [
            null as TransactionalEmailResultsApi | null,
            {
                loadResults: async (_: void, breakpoint) => {
                    const { workflowId, event, windowDays, revenueProperty } = values.resultsQuery
                    if (values.currentProjectId === null || !workflowId || !event) {
                        return null
                    }
                    await breakpoint(300)
                    const response = await transactionalEmailLogResultsRetrieve(String(values.currentProjectId), {
                        workflow_id: workflowId,
                        event,
                        window_days: windowDays,
                        revenue_property: revenueProperty ?? undefined,
                        date_from: dayjs().subtract(values.days, 'day').toISOString(),
                    })
                    breakpoint()
                    return response
                },
            },
        ],
    })),
    selectors({
        canLoadResults: [
            (s) => [s.resultsQuery],
            (query: ResultsQuery): boolean => !!query.workflowId && !!query.event,
        ],
    }),
    listeners(({ actions, values }) => ({
        setDays: () => {
            actions.loadTemplateStats()
            actions.loadDomainStats()
            if (values.canLoadResults) {
                actions.loadResults()
            }
        },
        setResultsQuery: () => {
            if (values.canLoadResults) {
                actions.loadResults()
            }
        },
        loadResultsSuccess: ({ results }) => {
            if (results) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('transactional email results calculated', {
                    window_days: values.resultsQuery.windowDays,
                    has_revenue_property: !!values.resultsQuery.revenueProperty,
                    recipients: results.recipients,
                    converted: results.converted,
                })
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadTemplateStats()
        actions.loadDomainStats()
    }),
])

async function fetchStats(
    projectId: number | null,
    groupBy: 'template' | 'sending_domain',
    days: number
): Promise<TransactionalEmailStatsRowApi[]> {
    if (projectId === null) {
        return []
    }
    const response = await transactionalEmailLogStatsRetrieve(String(projectId), {
        group_by: groupBy,
        date_from: dayjs().subtract(days, 'day').toISOString(),
    })
    return [...response.results]
}
