export const deliveryWebhooksLogic = kea<deliveryWebhooksLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'webhooks', 'deliveryWebhooksLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentTeamId', 'currentTeamLoading']],
        actions: [teamLogic, ['updateCurrentTeam']],
    })),
    actions({
        openAddModal: true,
        closeAddModal: true,
        setCreatedSecret: (secret: string | null) => ({ secret }),
        enableEngagementEvents: true,
    }),
    reducers({
        isAddModalOpen: [
            false,
            {
                openAddModal: () => true,
                closeAddModal: () => false,
            },
        ],
        // The secret is encrypted on save and never readable again, so the modal shows it once and then drops it.
        createdSecret: [
            null as string | null,
            {
                setCreatedSecret: (_, { secret }) => secret,
                closeAddModal: () => null,
            },
        ],
    }),
    selectors({
        engagementEventsEnabled: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): boolean =>
                !!currentTeam?.workflows_config?.capture_workflows_engagement_events,
        ],
    }),
    forms(({ values, actions }) => ({
        webhookForm: {
            defaults: DEFAULT_FORM,
            errors: ({ url, events }: DeliveryWebhookForm) => ({
                url: isHttpsUrl(url.trim()) ? undefined : 'Enter a URL that starts with https://',
                // kea-forms types an array field's error as an array, but LemonField shows one message for the whole list.
                events: events.length === 0 ? ('Choose at least one event' as any) : undefined,
            }),
            submit: async ({ url, events, receivedRecipient }: DeliveryWebhookForm) => {
                // The route takes the team id, so the destination lands in the active environment, not its project's primary one.
                const projectId = String(values.currentTeamId)
                const template = await hogFunctionTemplatesRetrieve(projectId, DELIVERY_WEBHOOK_TEMPLATE_ID)
                const signingSecret = generateSigningSecret()
                await hogFunctionsCreate(
                    projectId,
                    buildDeliveryWebhookPayload({ url: url.trim(), events, receivedRecipient, signingSecret, template })
                )
                actions.setCreatedSecret(signingSecret)
            },
        },
    })),
    listeners(({ actions, values }) => ({
        openAddModal: () => {
            // pinned: analytics event name
            posthog.capture('transactional_webhook_add_opened')
            // Delivery events need engagement events, which count toward usage. Received email doesn't.
            if (!values.engagementEventsEnabled) {
                actions.setWebhookFormValue('events', [RECEIVED_EMAIL_EVENT])
            }
        },
        closeAddModal: () => {
            actions.resetWebhookForm()
        },
        submitWebhookFormSuccess: () => {
            // pinned: analytics event name
            posthog.capture('transactional_webhook_created', { event_count: values.webhookForm.events.length })
            hogFunctionsListLogic.findMounted(DELIVERY_WEBHOOK_LIST_PROPS)?.actions.loadHogFunctions()
        },
        submitWebhookFormFailure: ({ error }) => {
            lemonToast.error(`Couldn't create the webhook: ${error?.message ?? 'unknown error'}. Try again.`)
        },
        enableEngagementEvents: () => {
            // pinned: analytics event name
            posthog.capture('transactional_webhook_engagement_events_enabled')
            // The API merges a partial config, so sending one key cannot overwrite a setting changed in another tab.
            actions.updateCurrentTeam({ workflows_config: { capture_workflows_engagement_events: true } })
        },
    })),
])
