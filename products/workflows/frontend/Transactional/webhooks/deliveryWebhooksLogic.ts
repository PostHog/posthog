export const deliveryWebhooksLogic = kea<deliveryWebhooksLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'webhooks', 'deliveryWebhooksLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentTeamId', 'currentTeamLoading']],
        actions: [teamLogic, ['updateCurrentTeam']],
    })),
    actions({
        openAddModal: true,
        closeAddModal: true,
        setCreatedSecret: (secret: string | null) => ({ secret }),
        enableEngagementEvents: true,
    }),
    reducers({
        isAddModalOpen: [
            false,
            {
                openAddModal: () => true,
                closeAddModal: () => false,
            },
        ],
        transactionalEmailOptionsError: [
            null as TransactionalEmailOptionsError | null,
            {
                loadTransactionalEmailOptions: () => null,
                loadTransactionalEmailOptionsFailure: (_, { error, errorObject }) => ({
                    message: withoutFinalPeriod(error),
                    accessDenied: errorObject?.status === 403,
                }),
            },
        ],
        createdSecret: [
            null as string | null,
            {
                setCreatedSecret: (_, { secret }) => secret,
                closeAddModal: () => null,
            },
        ],
    }),
    selectors({
        engagementEventsEnabled: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): boolean =>
                !!currentTeam?.workflows_config?.capture_workflows_engagement_events,
        ],
    }),
    loaders(({ values }) => ({
        transactionalEmailOptions: [
            [] as TransactionalEmailOption[],
            {
                loadTransactionalEmailOptions: async () => {
                    const projectId = String(values.currentTeamId)
                    const templates = await listAllPages((params) =>
                        messagingTemplatesList(projectId, { ...params, transactional: true, basic: true })
                    )
                    const transactional = templates.flatMap(({ transactional_hog_flow_id, ...template }) =>
                        transactional_hog_flow_id ? [{ ...template, transactional_hog_flow_id }] : []
                    )
                    const nameCounts = new Map<string, number>()
                    for (const { name } of transactional) {
                        nameCounts.set(name, (nameCounts.get(name) ?? 0) + 1)
                    }
                    return transactional.map((template) => ({
                        key: template.transactional_hog_flow_id,
                        label:
                            nameCounts.get(template.name)! > 1
                                ? `${template.name} (${template.id.slice(-8)})`
                                : template.name,
                    }))
                },
            },
        ],
    })),
    forms(({ values, actions }) => ({
        webhookForm: {
            defaults: DEFAULT_FORM,
            errors: ({ url, events }: DeliveryWebhookForm) => ({
                url: isHttpsUrl(url.trim()) ? undefined : 'Enter a URL that starts with https://',
                events: events.length === 0 ? ('Choose at least one event' as any) : undefined,
            }),
            submit: async ({ url, events, workflowIds }: DeliveryWebhookForm) => {
                const projectId = String(values.currentTeamId)
                const signingSecret = generateSigningSecret()
                try {
                    await hogFunctionsCreate(
                        projectId,
                        buildDeliveryWebhookPayload({ url: url.trim(), events, workflowIds, signingSecret })
                    )
                } catch (error: any) {
                    lemonToast.error(
                        `Couldn't create the webhook: ${withoutFinalPeriod(error?.message ?? 'unknown error')}. Try again.`
                    )
                    throw error
                }
                actions.setCreatedSecret(signingSecret)
            },
        },
    })),
    listeners(({ actions, values }) => ({
        openAddModal: () => {
            actions.loadTransactionalEmailOptions()
            posthog.capture('transactional_webhook_add_opened')
        },
        closeAddModal: () => {
            actions.resetWebhookForm()
        },
        submitWebhookFormSuccess: () => {
            posthog.capture('transactional_webhook_created', {
                event_count: values.webhookForm.events.length,
                email_filter_count: values.webhookForm.workflowIds.length,
            })
            hogFunctionsListLogic.findMounted(DELIVERY_WEBHOOK_LIST_PROPS)?.actions.loadHogFunctions()
        },
        enableEngagementEvents: () => {
            posthog.capture('transactional_webhook_engagement_events_enabled')
            actions.updateCurrentTeam({ workflows_config: { capture_workflows_engagement_events: true } })
        },
    })),
])
