import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { uuid } from 'lib/utils/dom'

import { SurveyEventName, SurveyEventProperties } from '~/types'

import { SurveyAnswer, captureSurveyResponse } from '../../surveyResponseCapture'

export interface ComingSoonInterestLogicProps {
    /** An `api`-type survey with a single-choice question then an open one. */
    surveyId: string
    interestQuestionId: string
    noteQuestionId: string
    surface: string
    /** The signed-in person's uuid. Answers are stored per person, because they live in a shared browser. */
    accountId: string
}

// pinned: the survey's first choice, which the results and the customer call list read
const INTERESTED_RESPONSE = 'Interested'

// The second click of a double click lands on the modal overlay, which would close the modal it just opened.
const DOUBLE_CLICK_MS = 500

const PATH_PREFIX = ['products', 'workflows', 'frontend', 'Transactional', 'comingSoon', 'comingSoonInterestLogic']

interface SavedAnswers {
    submissionId: string
    note: string
    noteSent: boolean
}

// Answers were once stored per survey, not per account. Only the account that wrote them may take them over.
function takeLegacyAnswers({ surveyId, accountId }: ComingSoonInterestLogicProps): SavedAnswers | null {
    if (!accountId) {
        return null
    }
    const legacyKey = (reducer: string): string => [...PATH_PREFIX, surveyId, reducer].join('.')
    try {
        const read = (reducer: string): unknown => JSON.parse(localStorage.getItem(legacyKey(reducer)) ?? 'null')
        if (read('submissionId') !== accountId) {
            return null
        }
        const answers = {
            submissionId: accountId,
            note: String(read('note') ?? ''),
            noteSent: read('noteSent') === true,
        }
        for (const reducer of ['submissionId', 'note', 'noteSent']) {
            localStorage.removeItem(legacyKey(reducer))
        }
        return answers
    } catch {
        return null
    }
}

function interestAnswer({ interestQuestionId }: ComingSoonInterestLogicProps): SurveyAnswer {
    return { questionIndex: 0, questionId: interestQuestionId, value: INTERESTED_RESPONSE }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface comingSoonInterestLogicValues {
    hasRecordedInterest: boolean
    note: string
    noteOpen: boolean
    noteSent: boolean
    submissionId: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface comingSoonInterestLogicActions {
    closeNote: () => {
        value: true
    }
    interestRecorded: (submissionId: string) => {
        submissionId: string
    }
    legacyAnswersRestored: (answers: SavedAnswers) => {
        answers: SavedAnswers
    }
    noteClosed: () => {
        value: true
    }
    noteSubmitted: () => {
        value: true
    }
    registerInterest: () => {
        value: true
    }
    setNote: (note: string) => {
        note: string
    }
    submitNote: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface comingSoonInterestLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        hasRecordedInterest: (submissionId: string | null) => boolean
    }
}

export type comingSoonInterestLogicType = MakeLogicType<
    comingSoonInterestLogicValues,
    comingSoonInterestLogicActions,
    ComingSoonInterestLogicProps,
    comingSoonInterestLogicMeta
>

export const comingSoonInterestLogic = kea<comingSoonInterestLogicType>([
    props({} as ComingSoonInterestLogicProps),
    key(({ surveyId, accountId }) => `${surveyId}/${accountId}`),
    // pinned: the path names the localStorage keys that remember a person's interest
    path((key) => [...PATH_PREFIX, key]),
    actions({
        registerInterest: true,
        interestRecorded: (submissionId: string) => ({ submissionId }),
        legacyAnswersRestored: (answers: SavedAnswers) => ({ answers }),
        closeNote: true,
        noteClosed: true,
        setNote: (note: string) => ({ note }),
        submitNote: true,
        noteSubmitted: true,
    }),
    reducers({
        submissionId: [
            null as string | null,
            { persist: true },
            {
                interestRecorded: (_, { submissionId }) => submissionId,
                legacyAnswersRestored: (_, { answers }) => answers.submissionId,
            },
        ],
        noteOpen: [
            false,
            {
                registerInterest: () => true,
                noteClosed: () => false,
                noteSubmitted: () => false,
            },
        ],
        note: [
            '',
            { persist: true },
            {
                setNote: (_, { note }) => note,
                legacyAnswersRestored: (_, { answers }) => answers.note,
            },
        ],
        noteSent: [
            false,
            { persist: true },
            {
                noteSubmitted: () => true,
                legacyAnswersRestored: (_, { answers }) => answers.noteSent,
            },
        ],
    }),
    selectors({
        hasRecordedInterest: [(s) => [s.submissionId], (submissionId: string | null): boolean => !!submissionId],
    }),
    listeners(({ actions, values, props, cache }) => ({
        closeNote: () => {
            if (Date.now() - cache.noteOpenedAt >= DOUBLE_CLICK_MS) {
                actions.noteClosed()
            }
        },
        registerInterest: () => {
            cache.noteOpenedAt = Date.now()
            // The note event repeats the interest, so after a note there is nothing left to send.
            if (values.noteSent) {
                return
            }
            // Each click resends under the same id, so an event lost offline gets another chance and still counts once.
            // The person's id keeps one response across tabs and browsers, which the persisted state cannot reach.
            const submissionId = values.submissionId ?? (props.accountId || uuid())
            actions.interestRecorded(submissionId)
            captureSurveyResponse({
                surveyId: props.surveyId,
                submissionId,
                completed: false,
                answers: [interestAnswer(props)],
                surface: props.surface,
            })
        },
        submitNote: () => {
            const note = values.note.trim()
            if (!note || !values.submissionId) {
                return
            }
            captureSurveyResponse({
                surveyId: props.surveyId,
                submissionId: values.submissionId,
                completed: true,
                // The survey results table reads a submission from its latest event, so the note
                // event repeats the interest answer to keep it on the row.
                answers: [interestAnswer(props), { questionIndex: 1, questionId: props.noteQuestionId, value: note }],
                surface: props.surface,
            })
            actions.noteSubmitted()
            lemonToast.success('Thanks, we got your note')
        },
    })),
    afterMount(({ actions, values, props }) => {
        const legacyAnswers = values.submissionId ? null : takeLegacyAnswers(props)
        if (legacyAnswers) {
            actions.legacyAnswersRestored(legacyAnswers)
        }
        if (!values.hasRecordedInterest) {
            posthog.capture(SurveyEventName.SHOWN, {
                [SurveyEventProperties.SURVEY_ID]: props.surveyId,
                feedback_surface: props.surface,
            })
        }
    }),
])
