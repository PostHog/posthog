export const afterClickingScanLogic = kea<afterClickingScanLogicType>([
    props({} as AfterClickingScanLogicProps),
    key((props) => `${props.workflowId}:${props.days}:${props.linkTagging}`),
    path((key) => ['products', 'workflows', 'frontend', 'Transactional', 'impact', 'afterClickingScanLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentTeamId', 'currentTeam']] })),
    actions({
        scanSessions: true,
        setScanRequest: (request: ObservationRequestApi) => ({ request }),
        failScan: (error: unknown) => ({ error }),
    }),
    loaders(({ props, values }) => ({
        sessions: [
            null as TransactionalEmailImpactSessionsApi | null,
            {
                loadSessions: async (_: void, breakpoint) => {
                    try {
                        return await transactionalEmailLogImpactSessionsRetrieve(String(values.currentTeamId), {
                            workflow_id: props.workflowId,
                            date_from: dayjs()
                                .subtract(props.days * 24, 'hour')
                                .toISOString(),
                            landed_before: dayjs().subtract(24, 'hour').toISOString(),
                        })
                    } finally {
                        breakpoint()
                    }
                },
            },
        ],
    })),
    reducers({
        scanRequest: [null as ObservationRequestApi | null, { setScanRequest: (_, { request }) => request }],
        scanStarting: [false, { scanSessions: () => true, setScanRequest: () => false, failScan: () => false }],
        scanError: [null as unknown, { scanSessions: () => null, failScan: (_, { error }) => error }],
    }),
    selectors({
        sessionIds: [
            (s) => [s.sessions],
            (sessions): string[] => sessions?.sessions.map(({ session_id }) => session_id) ?? [],
        ],
        scanState: [
            (s) => [s.sessions, s.sessionIds, s.sessionsLoading, s.scanRequest, s.scanStarting, s.scanError],
            (
                sessions: afterClickingScanLogicValues['sessions'],
                sessionIds: afterClickingScanLogicValues['sessionIds'],
                sessionsLoading: afterClickingScanLogicValues['sessionsLoading'],
                scanRequest: afterClickingScanLogicValues['scanRequest'],
                scanStarting: afterClickingScanLogicValues['scanStarting'],
                scanError: afterClickingScanLogicValues['scanError']
            ): AfterClickingScanState => {
                if (scanError) {
                    return { kind: 'scan-error', message: scanErrorMessage(scanError, !!scanRequest) }
                }
                if (scanRequest) {
                    return scanRequestState(scanRequest)
                }
                if (scanStarting) {
                    return { kind: 'scanning', done: 0, total: sessionIds.length }
                }
                if (sessionsLoading) {
                    return { kind: 'loading-sessions' }
                }
                if (!sessions) {
                    return { kind: 'sessions-error' }
                }
                if (sessionIds.length === 0) {
                    return { kind: 'no-sessions' }
                }
                return { kind: 'ready', sessionCount: sessionIds.length, hasMore: sessions.has_more }
            },
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        scanSessions: async (_, breakpoint) => {
            cache.disposables.dispose('scanPoll')
            if (!values.scanRequest && !cache.scanKey) {
                cache.scanKey = uuid()
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('transactional email impact scan started', {
                    sessions: values.sessionIds.length,
                    days: props.days,
                })
            }
            let request: ObservationRequestApi
            try {
                request = values.scanRequest
                    ? await visionRequestsRetrieve(String(values.currentTeamId), values.scanRequest.id)
                    : await visionRequestsCreate(String(values.currentTeamId), {
                          session_ids: values.sessionIds,
                          inline: { prompt: SCAN_PROMPT, scanner_config: { allow_inconclusive: true } },
                          reference: `workflows-email:${props.workflowId}`,
                          idempotency_key: cache.scanKey,
                      })
            } catch (error) {
                breakpoint()
                actions.failScan(error)
                return
            }
            breakpoint()
            actions.setScanRequest(request)
        },
        setScanRequest: ({ request }) => {
            if (request.status === 'running') {
                cache.disposables.add(() => {
                    const timer = setTimeout(() => actions.scanSessions(), SCAN_POLL_INTERVAL_MS)
                    return () => clearTimeout(timer)
                }, 'scanPoll')
                return
            }
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('transactional email impact scan completed', {
                sessions: request.sessions.length,
                answered: request.sessions.filter((session) => sessionAnswer(session)).length,
                days: props.days,
            })
        },
        failScan: ({ error }) => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('transactional email impact scan failed', {
                stage: values.scanRequest ? 'poll' : 'start',
                status: error instanceof ApiError ? (error.status ?? null) : null,
                days: props.days,
            })
        },
    })),
    afterMount(({ actions }) => actions.loadSessions()),
])
