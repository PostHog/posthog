// A new period gets its own logic, so nothing from the old period's scan reaches it.
export const afterClickingScanLogic = kea<afterClickingScanLogicType>([
    props({} as AfterClickingScanLogicProps),
    key((props) => `${props.workflowId}:${props.days}`),
    path((key) => ['products', 'workflows', 'frontend', 'Transactional', 'impact', 'afterClickingScanLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    loaders(({ props, values }) => ({
        sessions: [
            null as TransactionalEmailImpactSessionsApi | null,
            {
                loadSessions: async () =>
                    await transactionalEmailLogImpactSessionsRetrieve(String(values.currentTeamId), {
                        workflow_id: props.workflowId,
                        date_from: dayjs()
                            .subtract(props.days * 24, 'hour')
                            .toISOString(),
                    }),
            },
        ],
        scanRequest: [
            null as ObservationRequestApi | null,
            {
                startScan: async () =>
                    await visionRequestsCreate(String(values.currentTeamId), {
                        session_ids: (values.sessions?.sessions ?? []).map((session) => session.session_id),
                        inline: { prompt: SCAN_PROMPT },
                        reference: `workflows-email:${props.workflowId}`,
                        idempotency_key: uuid(),
                    }),
                refreshScan: async () =>
                    values.scanRequest
                        ? await visionRequestsRetrieve(String(values.currentTeamId), values.scanRequest.id)
                        : null,
            },
        ],
    })),
    reducers({
        scanStarting: [false, { startScan: () => true, startScanSuccess: () => false, startScanFailure: () => false }],
        sessionsFailed: [
            false,
            { loadSessions: () => false, loadSessionsSuccess: () => false, loadSessionsFailure: () => true },
        ],
        scanError: [
            null as string | null,
            {
                startScan: () => null,
                startScanFailure: (_, { errorObject }) => scanErrorMessage(errorObject),
                refreshScanFailure: (_, { errorObject }) => scanErrorMessage(errorObject),
            },
        ],
    }),
    selectors({
        scanState: [
            (s) => [s.sessions, s.sessionsLoading, s.sessionsFailed, s.scanRequest, s.scanStarting, s.scanError],
            (
                sessions: TransactionalEmailImpactSessionsApi | null,
                sessionsLoading: boolean,
                sessionsFailed: boolean,
                scanRequest: ObservationRequestApi | null,
                scanStarting: boolean,
                scanError: string | null
            ): AfterClickingScanState => {
                if (scanError) {
                    return { kind: 'scan-error', message: scanError }
                }
                if (scanStarting) {
                    return { kind: 'scanning', done: 0, total: sessions?.sessions.length ?? 0 }
                }
                if (scanRequest) {
                    return scanRequestState(scanRequest)
                }
                if (sessionsFailed) {
                    return { kind: 'sessions-error' }
                }
                if (sessionsLoading || !sessions) {
                    return { kind: 'loading-sessions' }
                }
                if (sessions.sessions.length === 0) {
                    return { kind: 'no-sessions' }
                }
                return { kind: 'ready', sessionCount: sessions.sessions.length, hasMore: sessions.has_more }
            },
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        const follow = (request: ObservationRequestApi | null): void => {
            if (request?.status === 'running') {
                cache.disposables.add(() => {
                    const timer = setTimeout(() => actions.refreshScan(), SCAN_POLL_INTERVAL_MS)
                    return () => clearTimeout(timer)
                }, 'scanPoll')
            } else {
                // The plugin restarts a registered timer when the tab comes back, which would poll a finished scan.
                cache.disposables.dispose('scanPoll')
            }
        }
        return {
            startScan: () => {
                cache.disposables.dispose('scanPoll')
                posthog.capture('transactional email impact scan started', {
                    sessions: values.sessions?.sessions.length ?? 0,
                    days: props.days,
                })
            },
            startScanSuccess: ({ scanRequest }) => follow(scanRequest),
            refreshScanSuccess: ({ scanRequest }) => follow(scanRequest),
            refreshScanFailure: () => cache.disposables.dispose('scanPoll'),
        }
    }),
    afterMount(({ actions }) => actions.loadSessions()),
])
