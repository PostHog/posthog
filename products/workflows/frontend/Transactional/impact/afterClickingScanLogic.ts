export const SCAN_POLL_INTERVAL_MS = 3000
export const SCAN_QUESTION = 'Did the person finish what they came to do?'
const SCAN_PROMPT = `At some point in this session the person clicked a link in an email and landed on a page whose URL has a ph_workflow_run parameter. Look only at what they did from that page on, and answer this question: ${SCAN_QUESTION}`

export interface AfterClickingScanLogicProps {
    workflowId: string
    days: number
}

export interface SessionAnswer {
    sessionId: string
    verdict: MonitorVerdict
    reasoning: string
}

export type ScanBlockedState =
    | { kind: 'not-main-environment' }
    | { kind: 'no-access'; reason: string }
    | { kind: 'link-tagging-off' }
    | { kind: 'sensitive-email' }

export type AfterClickingScanState =
    | { kind: 'loading-sessions' }
    | { kind: 'sessions-error' }
    | { kind: 'no-sessions' }
    | { kind: 'ready'; sessionCount: number; hasMore: boolean }
    | { kind: 'scanning'; done: number; total: number }
    | { kind: 'finished'; answers: SessionAnswer[]; withoutAnswer: number }
    | { kind: 'scan-error'; message: string }

export function scanBlockedState(
    currentTeam: TeamPublicType | TeamType | null,
    linkTagging: LinkTagging
): ScanBlockedState | null {
    // Scan requests live in the project's main environment, and the API refuses them from any other.
    if (currentTeam?.project_id && currentTeam.id !== currentTeam.project_id) {
        return { kind: 'not-main-environment' }
    }
    const reason = getReplayVisionEditDisabledReason()
    if (reason) {
        return { kind: 'no-access', reason }
    }
    if (linkTagging === 'off') {
        return { kind: 'link-tagging-off' }
    }
    if (linkTagging === 'sensitive-email') {
        return { kind: 'sensitive-email' }
    }
    return null
}

function scanErrorMessage(error: unknown): string {
    const shown = error instanceof ApiError && (error.status === 400 || error.status === 403) && error.detail
    return shown || "Replay vision couldn't scan these sessions. Try again."
}

function sessionAnswer(session: ObservationRequestSessionApi): SessionAnswer | null {
    const output = session.scanner_result?.model_output as Record<string, unknown> | null | undefined
    const verdict = output?.verdict
    if (verdict !== 'yes' && verdict !== 'no' && verdict !== 'inconclusive') {
        return null
    }
    return { sessionId: session.session_id, verdict, reasoning: String(output?.reasoning ?? '') }
}

function scanRequestState(request: ObservationRequestApi): AfterClickingScanState {
    if (request.status !== 'completed') {
        const done = request.sessions.filter((session) => session.state !== 'pending' && session.state !== 'running')
        return { kind: 'scanning', done: done.length, total: request.sessions.length }
    }
    const answers = request.sessions.map(sessionAnswer).filter((answer): answer is SessionAnswer => answer !== null)
    return { kind: 'finished', answers, withoutAnswer: request.sessions.length - answers.length }
}

