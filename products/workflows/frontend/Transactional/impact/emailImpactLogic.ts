function impactErrorMessage(error: { status?: number; detail?: string | null } | undefined): string {
    if (error?.status === 403 && error.detail) {
        return error.detail
    }
    if (error?.status === 429) {
        return 'Too many queries are running right now. Wait a few seconds, then try again.'
    }
    return !error?.status || error.status >= 500
        ? "This email's impact couldn't load. Try again, or pick a shorter period."
        : "This email's impact couldn't load. Try again, and if it keeps failing, contact support."
}

// Each query holds one of the organization's query slots until it finishes, even after the tab stops wanting
// its answer or closes. A newer change, or a reopened tab, waits for the running query instead of running beside it.
const runningQueries = new Map<string, Promise<unknown>>()

// A response that never arrives would otherwise hold the tab on its loading state until a page reload.
// After this limit the tab runs its query beside the unanswered one.
export const RUNNING_QUERY_WAIT_LIMIT_MS = 60_000

async function settledOrTimedOut(query: Promise<unknown>, ms: number): Promise<void> {
    let timer: ReturnType<typeof setTimeout> | undefined
    try {
        await Promise.race([query.catch(() => null), new Promise((resolve) => (timer = setTimeout(resolve, ms)))])
    } finally {
        clearTimeout(timer)
    }
}

export const emailImpactLogic = kea<emailImpactLogicType>([
    props({} as EmailImpactLogicProps),
    key((props) => props.workflowId),
    path((key) => ['products', 'workflows', 'frontend', 'Transactional', 'impact', 'emailImpactLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId', 'currentTeam']],
        actions: [teamLogic, ['loadCurrentTeamSuccess']],
    })),
    actions({
        setEvent: (event: string | null) => ({ event }),
        setDays: (days: number) => ({ days }),
        setAlwaysSensitive: (alwaysSensitive: boolean) => ({ alwaysSensitive }),
    }),
    reducers(({ props }) => ({
        // A selector that reads props keeps its result while the store is unchanged, so a template's new
        // sensitivity flag goes through the store.
        alwaysSensitive: [!!props.alwaysSensitive, { setAlwaysSensitive: (_, { alwaysSensitive }) => alwaysSensitive }],
        event: [null as string | null, { persist: true }, { setEvent: (_, { event }) => event }],
        days: [30 as number, { setDays: (_, { days }) => days }],
        impactError: [
            null as string | null,
            {
                loadImpact: () => null,
                loadImpactSuccess: () => null,
                loadImpactFailure: (_, { errorObject }) => impactErrorMessage(errorObject),
            },
        ],
    })),
    loaders(({ props, values }) => ({
        impact: [
            null as TransactionalEmailImpactApi | null,
            {
                loadImpact: async (_: void, breakpoint) => {
                    if (values.currentTeamId === null) {
                        return null
                    }
                    await breakpoint(100)
                    const waitUntil = Date.now() + RUNNING_QUERY_WAIT_LIMIT_MS
                    for (
                        let running = runningQueries.get(props.workflowId);
                        running && Date.now() < waitUntil;
                        running = runningQueries.get(props.workflowId)
                    ) {
                        await settledOrTimedOut(running, waitUntil - Date.now())
                        breakpoint()
                    }
                    const query = transactionalEmailLogImpactRetrieve(String(values.currentTeamId), {
                        workflow_id: props.workflowId,
                        event: values.event ?? undefined,
                        date_from: dayjs()
                            .subtract(values.days * 24, 'hour')
                            .toISOString(),
                    })
                    runningQueries.set(props.workflowId, query)
                    try {
                        return await query
                    } finally {
                        // A query that answers after the wait limit must not drop the entry of the one that replaced it.
                        if (runningQueries.get(props.workflowId) === query) {
                            runningQueries.delete(props.workflowId)
                        }
                        breakpoint()
                    }
                },
            },
        ],
        storedLinkTagging: [
            null as boolean | null,
            {
                loadStoredLinkTagging: async (_: void, breakpoint) => {
                    const { organization, project_id } = values.currentTeam ?? {}
                    if (!organization || !project_id) {
                        return values.storedLinkTagging
                    }
                    let project: ProjectBackwardCompatApi | null
                    try {
                        project = await organizationsProjectsRetrieve(organization, project_id)
                    } catch {
                        project = null
                    }
                    breakpoint()
                    return project
                        ? (project.workflows_config?.email_workflow_run_link_tag_enabled ?? true)
                        : values.storedLinkTagging
                },
            },
        ],
    })),
    selectors({
        funnelState: [
            (s) => [s.impact, s.impactLoading, s.impactError],
            (
                impact: TransactionalEmailImpactApi | null,
                impactLoading: boolean,
                impactError: string | null
            ): ImpactFunnelState => impactFunnelState(impact, impactLoading, impactError),
        ],
        linkTagging: [
            (s) => [s.storedLinkTagging, s.currentTeam, s.alwaysSensitive],
            (
                storedLinkTagging: boolean | null,
                currentTeam: TeamPublicType | TeamType | null,
                alwaysSensitive: boolean
            ): LinkTagging =>
                alwaysSensitive
                    ? 'sensitive-email'
                    : (storedLinkTagging ?? currentTeam?.workflows_config?.email_workflow_run_link_tag_enabled ?? true)
                      ? 'on'
                      : 'off',
        ],
        steps: [
            (s) => [s.impact, s.event, s.linkTagging],
            (
                impact: TransactionalEmailImpactApi | null,
                event: string | null,
                linkTagging: LinkTagging
            ): ImpactStep[] | null => (impact ? impactSteps(impact, event, linkTagging) : null),
        ],
        lift: [
            (s) => [s.impact],
            (impact: TransactionalEmailImpactApi | null): ImpactLift | null => (impact ? impactLift(impact) : null),
        ],
        followedNote: [
            (s) => [s.impact],
            (impact: TransactionalEmailImpactApi | null): string | null => (impact ? followedSendsNote(impact) : null),
        ],
        untrackedNote: [
            (s) => [s.impact],
            (impact: TransactionalEmailImpactApi | null): string | null => (impact ? untrackedSendsNote(impact) : null),
        ],
        replayEnabled: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | TeamPublicType | null): boolean => !!currentTeam?.session_recording_opt_in,
        ],
    }),
    listeners(({ actions, values }) => ({
        setEvent: () => actions.loadImpact(),
        setDays: () => actions.loadImpact(),
        loadCurrentTeamSuccess: () => {
            if (!values.impact && !values.impactLoading) {
                actions.loadImpact()
            }
        },
        loadImpactSuccess: ({ impact }) => {
            if (impact) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('transactional email impact loaded', {
                    has_event: !!values.event,
                    days: values.days,
                    has_untracked_sends: impact.untracked > 0,
                })
            }
        },
    })),
    propsChanged(({ actions, props }, oldProps) => {
        if (!!props.alwaysSensitive !== !!oldProps.alwaysSensitive) {
            actions.setAlwaysSensitive(!!props.alwaysSensitive)
        }
    }),
    afterMount(({ actions, cache }) => {
        actions.loadImpact()
        // The link tagging setting can change in another tab or window, including the one this tab's settings link
        // opens. kea-disposables runs this setup on mount and again each time the page is shown, and a settings window
        // beside this one hands focus back without a show, so the step reads the setting on all three. A read that
        // ran before a save committed, or that failed, is repaired by the next show or focus. The read stays out of
        // teamLogic, because a slow response there would replace a newer shared team.
        cache.disposables.add(() => {
            const refresh = (): void => actions.loadStoredLinkTagging()
            refresh()
            window.addEventListener('focus', refresh)
            return () => window.removeEventListener('focus', refresh)
        }, 'refreshLinkTagging')
    }),
])
