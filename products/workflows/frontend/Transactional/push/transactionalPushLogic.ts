export const transactionalPushLogic = kea<transactionalPushLogicType>([
    path((id) => ['products', 'workflows', 'frontend', 'Transactional', 'push', 'transactionalPushLogic', id]),
    props({} as TransactionalPushLogicProps),
    key((props) => props.id),
    connect(() => ({ values: [projectLogic, ['currentProjectId']] })),
    actions({
        setName: (name: string) => ({ name }),
        setDraft: (draft: Partial<PushDraft>) => ({ draft }),
        discardChanges: true,
        setTab: (tab: TransactionalPushTab) => ({ tab }),
        setTestDistinctId: (distinctId: string) => ({ distinctId }),
        setTestVariable: (name: string, value: string) => ({ name, value }),
    }),
    loaders(({ props, values }) => ({
        template: [
            null as MessageTemplateApi | null,
            {
                loadTemplate: async () => messagingTemplatesRetrieve(String(values.currentProjectId), props.id),
                saveTemplate: async () => {
                    try {
                        const saved = await messagingTemplatesPartialUpdate(String(values.currentProjectId), props.id, {
                            name: values.name.trim(),
                            content: { templating: 'liquid', push: pushContentFrom(values.draft) },
                        })
                        lemonToast.success(
                            saved.transactional_hog_flow_id ? 'Published. New sends use this version.' : 'Saved'
                        )
                        posthog.capture('transactional push saved', {
                            variable_count: values.variables.length,
                            channel_count: values.draft.channels.length,
                        })
                        return saved
                    } catch (error: any) {
                        lemonToast.error(`Couldn't save: ${errorDetail(error)}`)
                        return values.template
                    }
                },
                makeTransactional: async () => {
                    try {
                        const updated = await messagingTemplatesMakeTransactionalCreate(
                            String(values.currentProjectId),
                            props.id,
                            {}
                        )
                        lemonToast.success('This push notification can now be sent over the API')
                        return updated
                    } catch (error: any) {
                        lemonToast.error(`Couldn't make it sendable: ${errorDetail(error)}`)
                        return values.template
                    }
                },
            },
        ],
        lastTestSend: [
            null as string | null,
            {
                sendTest: async () => {
                    try {
                        const sent = await messagingSendPushCreate(String(values.currentProjectId), {
                            template_id: props.id,
                            distinct_id: values.testDistinctId.trim(),
                            message_data: values.testVariables,
                        })
                        lemonToast.success(
                            'Test sent. It reaches every device this person registered for the chosen apps.'
                        )
                        posthog.capture('transactional push test sent')
                        return sent.message_id
                    } catch (error: any) {
                        lemonToast.error(`Couldn't send the test: ${errorDetail(error)}`)
                        return values.lastTestSend
                    }
                },
            },
        ],
    })),
    reducers({
        name: [
            '',
            {
                setName: (_, { name }) => name,
                loadTemplateSuccess: (_, { template }) => template?.name ?? '',
                saveTemplateSuccess: (_, { template }) => template?.name ?? '',
            },
        ],
        draft: [
            EMPTY_PUSH_DRAFT as PushDraft,
            {
                setDraft: (state, { draft }) => ({ ...state, ...draft }),
                loadTemplateSuccess: (_, { template }) => pushDraftFrom(template?.content?.push),
                saveTemplateSuccess: (_, { template }) => pushDraftFrom(template?.content?.push),
            },
        ],
        tab: ['content' as TransactionalPushTab, { setTab: (_, { tab }) => tab }],
        loadError: [
            null as 'not_found' | 'failed' | null,
            {
                loadTemplate: () => null,
                loadTemplateSuccess: () => null,
                loadTemplateFailure: (_, { errorObject }) => (errorObject?.status === 404 ? 'not_found' : 'failed'),
            },
        ],
        testDistinctId: ['', { setTestDistinctId: (_, { distinctId }) => distinctId }],
        testVariables: [
            {} as Record<string, string>,
            { setTestVariable: (state, { name, value }) => ({ ...state, [name]: value }) },
        ],
    }),
    selectors({
        transactionalHogFlowId: [
            (s) => [s.template],
            (template: MessageTemplateApi | null): string | null => template?.transactional_hog_flow_id ?? null,
        ],
        savedDraft: [
            (s) => [s.template],
            (template: MessageTemplateApi | null): PushDraft => pushDraftFrom(template?.content?.push),
        ],
        hasChanges: [
            (s) => [s.draft, s.savedDraft, s.name, s.template],
            (draft: PushDraft, savedDraft: PushDraft, name: string, template: MessageTemplateApi | null): boolean =>
                JSON.stringify(draft) !== JSON.stringify(savedDraft) || name !== (template?.name ?? ''),
        ],
        dataError: [(s) => [s.draft], (draft: PushDraft): string | null => pushDataError(draft.data)],
        draftError: [(s) => [s.draft], (draft: PushDraft): string | null => pushDraftError(draft)],
        variables: [(s) => [s.draft], (draft: PushDraft): string[] => variablesInPush(draft)],
        publishBlockedReason: [
            (s) => [s.templateLoading, s.hasChanges, s.name, s.draftError],
            (templateLoading: boolean, hasChanges: boolean, name: string, draftError: string | null): string | null =>
                templateLoading
                    ? 'Loading'
                    : !hasChanges
                      ? 'No changes to publish'
                      : !name.trim()
                        ? 'Add a name'
                        : draftError,
        ],
        // A test goes out through the published version, so it asks for the variables that version reads.
        savedVariables: [(s) => [s.savedDraft], (savedDraft: PushDraft): string[] => variablesInPush(savedDraft)],
        breadcrumbs: [
            (s, p) => [p.id, s.template],
            (id: string, template: MessageTemplateApi | null): Breadcrumb[] => [
                {
                    key: Scene.Transactional,
                    name: 'Transactional',
                    path: urls.transactional(),
                    iconType: 'transactional',
                },
                {
                    key: [Scene.TransactionalPush, id],
                    name: template?.name || 'Push notification',
                    iconType: 'transactional',
                },
            ],
        ],
    }),
    listeners(({ actions, values }) => ({
        discardChanges: () => {
            if (values.template) {
                actions.loadTemplateSuccess(values.template)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadTemplate()
    }),
])
