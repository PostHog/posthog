import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { integrationsLogic } from 'lib/integrations/integrationsLogic'

import { IntegrationType } from '~/types'

import { countPeopleWithPushDevices, pushAppId } from '../../setupGuide/wizard/pushDeviceCheckLogic'

export type PushChannelsSetupWarning =
    // Every selected app was disconnected since the template was saved.
    | { kind: 'app_disconnected' }
    // The selected apps, none of which has a registered device.
    | { kind: 'no_devices'; appNames: string[] }
    // The device check failed, so whether anyone can get this notification is unknown.
    | { kind: 'check_failed' }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pushChannelsSetupLogicValues {
    integrations: IntegrationType[] | null // integrationsLogic
    channels: number[]
    deviceCounts: Record<string, number>
    deviceCountsFailed: boolean
    deviceCountsLoading: boolean
    selectedAppIds: string[]
    selectedIntegrations: IntegrationType[]
    warning: PushChannelsSetupWarning | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pushChannelsSetupLogicActions {
    loadIntegrationsSuccess: (
        integrations: IntegrationType[],
        payload?: any
    ) => {
        integrations: IntegrationType[]
        payload?: any
    } // integrationsLogic
    loadDeviceCounts: (appIds: string[]) => string[]
    loadDeviceCountsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadDeviceCountsSuccess: (
        deviceCounts: {
            [x: string]: number
        },
        payload?: string[]
    ) => {
        deviceCounts: {
            [x: string]: number
        }
        payload?: string[]
    }
    recheckDevices: () => {
        value: true
    }
    setChannels: (channels: number[]) => {
        channels: number[]
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pushChannelsSetupLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        selectedIntegrations: (integrations: IntegrationType[] | null, channels: number[]) => IntegrationType[]
        selectedAppIds: (selectedIntegrations: IntegrationType[]) => string[]
        warning: (
            integrations: IntegrationType[] | null,
            channels: number[],
            selectedIntegrations: IntegrationType[],
            deviceCounts: Record<string, number>,
            deviceCountsFailed: boolean
        ) => PushChannelsSetupWarning | null
    }
}

export type pushChannelsSetupLogicType = MakeLogicType<
    pushChannelsSetupLogicValues,
    pushChannelsSetupLogicActions,
    Record<string, any>,
    pushChannelsSetupLogicMeta
>

export const pushChannelsSetupLogic = kea<pushChannelsSetupLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'push', 'pushChannelsSetupLogic']),
    connect(() => ({
        values: [integrationsLogic, ['integrations']],
        actions: [integrationsLogic, ['loadIntegrationsSuccess']],
    })),
    actions({
        setChannels: (channels: number[]) => ({ channels }),
        recheckDevices: true,
    }),
    reducers({
        channels: [[] as number[], { setChannels: (_, { channels }) => channels }],
        deviceCountsFailed: [
            false,
            {
                loadDeviceCounts: () => false,
                loadDeviceCountsSuccess: () => false,
                loadDeviceCountsFailure: () => true,
            },
        ],
    }),
    loaders(({ values }) => ({
        // People with a registered device, by app. An app missing from it has not been counted yet.
        deviceCounts: [
            {} as Record<string, number>,
            {
                loadDeviceCounts: async (appIds: string[], breakpoint) => {
                    const counts = await countPeopleWithPushDevices(appIds, 'transactional_push_channel_devices')
                    breakpoint()
                    return { ...values.deviceCounts, ...counts }
                },
            },
        ],
    })),
    selectors({
        selectedIntegrations: [
            (s) => [s.integrations, s.channels],
            (integrations: IntegrationType[] | null, channels: number[]): IntegrationType[] =>
                (integrations ?? []).filter(
                    (integration) =>
                        (integration.kind === 'apns' || integration.kind === 'firebase') &&
                        channels.includes(integration.id)
                ),
        ],
        selectedAppIds: [
            (s) => [s.selectedIntegrations],
            (selected: IntegrationType[]): string[] =>
                [...new Set(selected.map(pushAppId))].filter((appId): appId is string => appId !== null),
        ],
        warning: [
            (s) => [s.integrations, s.channels, s.selectedIntegrations, s.deviceCounts, s.deviceCountsFailed],
            (
                integrations: IntegrationType[] | null,
                channels: number[],
                selected: IntegrationType[],
                deviceCounts: Record<string, number>,
                deviceCountsFailed: boolean
            ): PushChannelsSetupWarning | null => {
                if (integrations === null) {
                    return null
                }
                const hasPushIntegration = integrations.some(
                    (integration) => integration.kind === 'apns' || integration.kind === 'firebase'
                )
                // With no push app at all, the channel picker already says to connect one.
                if (selected.length === 0) {
                    return hasPushIntegration && channels.length > 0 ? { kind: 'app_disconnected' } : null
                }
                const counts = selected.map((integration) => {
                    const appId = pushAppId(integration)
                    return appId === null ? 0 : deviceCounts[appId]
                })
                if (counts.some((count) => count !== undefined && count > 0)) {
                    return null
                }
                if (counts.some((count) => count === undefined)) {
                    // A count still loading is not a verdict yet.
                    return deviceCountsFailed ? { kind: 'check_failed' } : null
                }
                return { kind: 'no_devices', appNames: selected.map((integration) => integration.display_name) }
            },
        ],
    }),
    listeners(({ actions, values }) => {
        const countNewApps = (): void => {
            const uncounted = values.selectedAppIds.filter((appId) => !(appId in values.deviceCounts))
            if (uncounted.length > 0) {
                actions.loadDeviceCounts(uncounted)
            }
        }
        return {
            setChannels: countNewApps,
            loadIntegrationsSuccess: countNewApps,
            recheckDevices: () => {
                if (values.selectedAppIds.length > 0) {
                    actions.loadDeviceCounts(values.selectedAppIds)
                }
            },
        }
    }),
])
