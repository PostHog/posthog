import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { projectLogic } from 'scenes/projectLogic'
import { urls } from 'scenes/urls'

import {
    messagingTemplatesCreate,
    messagingTemplatesMakeTransactionalCreate,
} from 'products/messaging/frontend/generated/api'

import { messageTemplatesLogic } from '../../TemplateLibrary/messageTemplatesLogic'
import { EMPTY_PUSH_DRAFT, PushDraft, pushContentFrom, pushDraftError } from './pushContent'

function errorDetail(error: any): string {
    return error?.detail || error?.message || 'unknown error'
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newTransactionalPushLogicValues {
    currentProjectId: number | null // projectLogic
    createDisabledReason: string | null
    draft: PushDraft
    isCreating: boolean
    isOpen: boolean
    name: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newTransactionalPushLogicActions {
    loadTemplates: () => any // messageTemplatesLogic
    closeModal: () => {
        value: true
    }
    create: () => {
        value: true
    }
    createFinished: () => {
        value: true
    }
    openModal: () => {
        value: true
    }
    setDraft: (draft: Partial<PushDraft>) => {
        draft: Partial<PushDraft>
    }
    setName: (name: string) => {
        name: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newTransactionalPushLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        createDisabledReason: (name: string, draft: PushDraft) => string | null
    }
}

export type newTransactionalPushLogicType = MakeLogicType<
    newTransactionalPushLogicValues,
    newTransactionalPushLogicActions,
    Record<string, any>,
    newTransactionalPushLogicMeta
>

export const newTransactionalPushLogic = kea<newTransactionalPushLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'push', 'newTransactionalPushLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
        actions: [messageTemplatesLogic, ['loadTemplates']],
    })),
    actions({
        openModal: true,
        closeModal: true,
        setName: (name: string) => ({ name }),
        setDraft: (draft: Partial<PushDraft>) => ({ draft }),
        create: true,
        createFinished: true,
    }),
    reducers({
        isOpen: [false, { openModal: () => true, closeModal: () => false }],
        name: ['', { setName: (_, { name }) => name, openModal: () => '' }],
        draft: [
            EMPTY_PUSH_DRAFT as PushDraft,
            { setDraft: (state, { draft }) => ({ ...state, ...draft }), openModal: () => EMPTY_PUSH_DRAFT },
        ],
        isCreating: [false, { create: () => true, createFinished: () => false }],
    }),
    selectors({
        createDisabledReason: [
            (s) => [s.name, s.draft],
            (name: string, draft: PushDraft): string | null => (!name.trim() ? 'Add a name' : pushDraftError(draft)),
        ],
    }),
    listeners(({ actions, values }) => ({
        create: async () => {
            const projectId = String(values.currentProjectId)
            let templateId: string
            try {
                const template = await messagingTemplatesCreate(projectId, {
                    name: values.name.trim(),
                    type: 'push',
                    content: { templating: 'liquid', push: pushContentFrom(values.draft) },
                })
                templateId = template.id
            } catch (error: any) {
                lemonToast.error(`Couldn't create the push notification: ${errorDetail(error)}`)
                actions.createFinished()
                return
            }
            try {
                await messagingTemplatesMakeTransactionalCreate(projectId, templateId, {})
                posthog.capture('transactional push created', { channel_count: values.draft.channels.length })
                lemonToast.success('Push notification created')
            } catch (error: any) {
                // The template exists either way. Its API tab offers "Make sendable" to try again.
                posthog.capture('transactional push creation failed', { step: 'make_transactional' })
                lemonToast.error(
                    `Saved, but it couldn't be made sendable: ${errorDetail(error)}. Try again from its API tab.`
                )
            }
            actions.createFinished()
            actions.closeModal()
            actions.loadTemplates()
            router.actions.push(urls.transactionalPush(templateId))
        },
    })),
])
