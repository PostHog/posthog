export const transactionalEmailsLogic = kea<transactionalEmailsLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'transactionalEmailsLogic']),
    connect(() => ({
        values: [
            transactionalTemplatesLogic,
            ['transactionalTemplates', 'transactionalTemplatesFailed', 'transactionalTemplatesLoading'],
            teamLogic,
            ['currentTeamId'],
        ],
        actions: [transactionalTemplatesLogic, ['loadTransactionalTemplates', 'setTemplateTags']],
    })),
    actions({
        setFilters: (filters: Partial<TransactionalEmailsFilters>) => ({ filters }),
        setFiltersFromUrl: (filters: TransactionalEmailsFilters) => ({ filters }),
        saveTransactionalTags: (row: TransactionalEmailRow, tags: string[]) => ({ row, tags }),
        transactionalTagsSaved: (rowId: string) => ({ rowId }),
        codeEmailChanged: (codeEmail: CodeEmailApi) => ({ codeEmail }),
    }),
    loaders(({ values }) => ({
        codeEmails: [
            null as CodeEmailApi[] | null,
            {
                loadCodeEmails: async () => {
                    try {
                        return await transactionalCodeEmailsList(String(values.currentTeamId))
                    } catch (error) {
                        // The endpoint answers 404 while the project can't send email from code yet.
                        if (error instanceof ApiError && error.status === 404) {
                            return []
                        }
                        throw error
                    }
                },
            },
        ],
    })),
    reducers(() => ({
        filters: [
            DEFAULT_FILTERS,
            // The list unmounts when an email opens, so the filters are persisted to survive that and be
            // restored when the user comes back to the list. The key carries the user and the team, so
            // another account or another project never reads these filters.
            buildUserScopedPersistenceConfig('transactional_emails_list_filters__'),
            {
                setFilters: (state, { filters }) => ({ ...state, ...filters }),
                setFiltersFromUrl: (_, { filters }) => filters,
            },
        ],
        savingTagsFor: [
            null as string | null,
            {
                saveTransactionalTags: (_, { row }) => row.id,
                transactionalTagsSaved: (state, { rowId }) => (state === rowId ? null : state),
            },
        ],
        codeEmails: {
            codeEmailChanged: (state, { codeEmail }) =>
                state?.map((email) => (email.id === codeEmail.id ? codeEmail : email)) ?? state,
        },
    })),
    selectors({
        transactionalEmails: [
            (s) => [s.transactionalTemplates, s.codeEmails],
            (templates: MessageTemplateApi[], codeEmails: CodeEmailApi[] | null): TransactionalEmailRow[] => [
                ...templates.map(templateRow),
                ...(codeEmails ?? []).map(codeEmailRow),
            ],
        ],
        filteredTransactionalEmails: [
            (s) => [s.transactionalEmails, s.filters],
            (rows: TransactionalEmailRow[], filters: TransactionalEmailsFilters): TransactionalEmailRow[] =>
                filterTransactionalEmails(rows, filters),
        ],
        isFiltered: [
            (s) => [s.filters],
            // Filters persisted before a filter existed lack it, so they are read over the defaults.
            (filters: TransactionalEmailsFilters): boolean =>
                !objectsEqual({ ...DEFAULT_FILTERS, ...filters }, DEFAULT_FILTERS),
        ],
    }),
    listeners(({ actions, values }) => {
        const changeCodeEmail = (codeEmail: CodeEmailApi): void => {
            transactionalEmailsLogic.findMounted()?.actions.codeEmailChanged(codeEmail)
        }

        // The editor builds each payload from the row's tags, so a second edit made while the first
        // is in flight would be built from the stored list and drop the first one. Showing the new
        // tags at once gives that second edit the right starting point.
        const showTagsAtOnce = (row: TransactionalEmailRow, tags: string[]): void => {
            if (row.source !== 'code') {
                actions.setTemplateTags(row.id, tags)
                return
            }
            if (!confirmedCodeEmails.has(row.id)) {
                confirmedCodeEmails.set(row.id, row.codeEmail)
            }
            actions.codeEmailChanged({ ...row.codeEmail, tags })
        }

        const saveCodeEmailTags = async (
            codeEmail: CodeEmailApi,
            tags: string[],
            isLatestEdit: () => boolean
        ): Promise<void> => {
            const updated = await transactionalCodeEmailsPartialUpdate(String(values.currentTeamId), codeEmail.id, {
                tags,
            })
            confirmedCodeEmails.set(codeEmail.id, updated)
            if (isLatestEdit()) {
                changeCodeEmail(updated)
            }
        }

        const saveTemplateTags = async (
            template: MessageTemplateApi,
            tags: string[],
            isLatestEdit: () => boolean
        ): Promise<void> => {
            const updated = await messagingTemplatesPartialUpdate(String(values.currentTeamId), template.id, { tags })
            if (isLatestEdit()) {
                actions.setTemplateTags(template.id, updated.tags ?? tags)
            }
        }

        // The row is showing tags that were never stored, so the stored ones are read back.
        const recoverCodeEmailTags = async (codeEmail: CodeEmailApi, isLatestEdit: () => boolean): Promise<void> => {
            if (!isLatestEdit()) {
                return
            }
            try {
                const stored = await transactionalCodeEmailsRetrieve(String(values.currentTeamId), codeEmail.id)
                if (isLatestEdit()) {
                    confirmedCodeEmails.set(codeEmail.id, stored)
                    changeCodeEmail(stored)
                }
            } catch {
                if (isLatestEdit()) {
                    changeCodeEmail(confirmedCodeEmails.get(codeEmail.id) ?? codeEmail)
                }
            }
        }

        return {
            saveTransactionalTags: async ({ row, tags }) => {
                showTagsAtOnce(row, tags)
                const isLatestEdit = startTagEdit(row.id)
                try {
                    await saveTagsAfterPause(row.id, () =>
                        saveInOrder(row.id, async () => {
                            if (!isLatestEdit()) {
                                return
                            }
                            return row.source === 'code'
                                ? saveCodeEmailTags(row.codeEmail, tags, isLatestEdit)
                                : saveTemplateTags(row.template, tags, isLatestEdit)
                        })
                    )
                } catch (error: any) {
                    lemonToast.error(`Couldn't save tags: ${error?.detail || error?.message || 'unknown error'}`)
                    if (row.source === 'code') {
                        await recoverCodeEmailTags(row.codeEmail, isLatestEdit)
                    } else if (isLatestEdit()) {
                        actions.loadTransactionalTemplates()
                    }
                } finally {
                    if (isLatestEdit()) {
                        confirmedCodeEmails.delete(row.id)
                    }
                    if (!pendingTagSaves.has(row.id)) {
                        actions.transactionalTagsSaved(row.id)
                    }
                }
            },
        }
    }),
    actionToUrl(({ values }) => ({
        setFilters: () => {
            const { search, createdBy, tags, managedBy } = { ...DEFAULT_FILTERS, ...values.filters }
            const searchParams = {
                ...router.values.searchParams,
                search: search || undefined,
                created_by: createdBy ?? undefined,
                tags: tags.length ? tags : undefined,
                managed_by: managedBy === 'all' ? undefined : managedBy,
            }
            return [router.values.location.pathname, searchParams, router.values.hashParams, { replace: true }]
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.transactional()]: (_, searchParams) => {
            // An in-app link back to the list, such as the breadcrumb out of an email, carries no filter
            // params. Parsing that URL would clear every filter, so the filters held in state are restored
            // and written back into the URL instead.
            if (!FILTER_URL_PARAMS.some((param) => param in searchParams)) {
                if (values.isFiltered) {
                    actions.setFilters(values.filters)
                }
                return
            }
            const rawTags = searchParams['tags']
            const createdBy = parseInt(String(searchParams['created_by']))
            const managedBy = MANAGED_BY_VALUES.find((value) => value === searchParams['managed_by'])
            const parsed: TransactionalEmailsFilters = {
                search: searchParams['search'] ? String(searchParams['search']) : '',
                createdBy: Number.isNaN(createdBy) ? null : createdBy,
                // kea-router parses a JSON array in the URL back into an array.
                tags: Array.isArray(rawTags)
                    ? rawTags.map(String)
                    : typeof rawTags === 'string' && rawTags
                      ? [rawTags]
                      : [],
                managedBy: managedBy ?? 'all',
            }
            if (!objectsEqual(parsed, values.filters)) {
                actions.setFiltersFromUrl(parsed)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadCodeEmails()
    }),
])

// The newest tag edit made on each row, so a save can tell when a later edit has replaced its tags.
const latestTagEdits = new Map<string, number>()

function startTagEdit(rowId: string): () => boolean {
    const edit = (latestTagEdits.get(rowId) ?? 0) + 1
    latestTagEdits.set(rowId, edit)
    return () => latestTagEdits.get(rowId) === edit
}

// The last tags the server confirmed for each email sent from code with edits in progress. A row already shows
// unsaved tags while a burst of edits waits, so it can't tell what to go back to when every save and read fails.
const confirmedCodeEmails = new Map<string, CodeEmailApi>()

// Writes on one row run one after another, so the server stores tags in the order the user made them.
const tagWrites = new Map<string, Promise<void>>()

function saveInOrder(rowId: string, save: () => Promise<void>): Promise<void> {
    const write = (tagWrites.get(rowId) ?? Promise.resolve()).catch(() => undefined).then(save)
    tagWrites.set(rowId, write)
    return write
}

// Tag writes waiting out their pause, keyed by row. They are held here rather than behind a
// listener breakpoint, which would also cancel them when another row is edited or the list unmounts.
const pendingTagSaves = new Map<string, () => void>()

// One write per burst of clicks on a row, so two quick edits become a single save that keeps both tags.
function saveTagsAfterPause(rowId: string, save: () => Promise<void>): Promise<void> {
    pendingTagSaves.get(rowId)?.()
    return new Promise<void>((resolve, reject) => {
        const timer = setTimeout(() => {
            pendingTagSaves.delete(rowId)
            save().then(resolve, reject)
        }, 300)
        pendingTagSaves.set(rowId, () => {
            clearTimeout(timer)
            resolve()
        })
    })
}
