import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import { buildUserScopedPersistenceConfig } from 'lib/logic/persistence'
import { objectsEqual } from 'lib/utils/objects'
import { urls } from 'scenes/urls'

import { filterMessageTemplates } from '../TemplateLibrary/filterMessageTemplates'
import { messageTemplatesLogic, saveTemplateTags } from '../TemplateLibrary/messageTemplatesLogic'
import { MessageTemplate } from '../TemplateLibrary/types'

export interface TransactionalEmailsFilters {
    search: string
    createdBy: number | null
    tags: string[]
}

const DEFAULT_FILTERS: TransactionalEmailsFilters = { search: '', createdBy: null, tags: [] }

// The search params actionToUrl writes below. A URL that carries none of them states no filters at all,
// which is different from stating that every filter is off.
const FILTER_URL_PARAMS = ['search', 'created_by', 'tags']

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface transactionalEmailsLogicValues {
    tags: string[] // messageTemplatesLogic
    templatesLoading: boolean // messageTemplatesLogic
    transactionalTemplates: MessageTemplate[] // messageTemplatesLogic
    filteredTransactionalTemplates: MessageTemplate[]
    filters: TransactionalEmailsFilters
    isFiltered: boolean
    savingTagsFor: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface transactionalEmailsLogicActions {
    loadTagsIfNeeded: () => {
        value: true
    } // messageTemplatesLogic
    saveTransactionalTags: (
        template: MessageTemplate,
        tags: string[]
    ) => {
        tags: string[]
        template: MessageTemplate
    }
    setFilters: (filters: Partial<TransactionalEmailsFilters>) => {
        filters: Partial<TransactionalEmailsFilters>
    }
    setFiltersFromUrl: (filters: TransactionalEmailsFilters) => {
        filters: TransactionalEmailsFilters
    }
    transactionalTagsSaved: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface transactionalEmailsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        filteredTransactionalTemplates: (transactionalTemplates: any, filters: any) => MessageTemplate[]
        isFiltered: (filters: any) => boolean
    }
}

export type transactionalEmailsLogicType = MakeLogicType<
    transactionalEmailsLogicValues,
    transactionalEmailsLogicActions,
    Record<string, any>,
    transactionalEmailsLogicMeta
>

export const transactionalEmailsLogic = kea<transactionalEmailsLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'transactionalEmailsLogic']),
    connect(() => ({
        values: [messageTemplatesLogic, ['transactionalTemplates', 'templatesLoading', 'tags']],
        actions: [messageTemplatesLogic, ['loadTagsIfNeeded']],
    })),
    actions({
        setFilters: (filters: Partial<TransactionalEmailsFilters>) => ({ filters }),
        setFiltersFromUrl: (filters: TransactionalEmailsFilters) => ({ filters }),
        saveTransactionalTags: (template: MessageTemplate, tags: string[]) => ({ template, tags }),
        transactionalTagsSaved: true,
    }),
    reducers(() => ({
        filters: [
            DEFAULT_FILTERS,
            // The list unmounts when an email opens, so the filters are persisted to survive that and be
            // restored when the user comes back to the list. The key carries the user and the team, so
            // another account or another project never reads these filters.
            buildUserScopedPersistenceConfig('transactional_emails_list_filters__'),
            {
                setFilters: (state, { filters }) => ({ ...state, ...filters }),
                setFiltersFromUrl: (_, { filters }) => filters,
            },
        ],
        savingTagsFor: [
            null as string | null,
            {
                saveTransactionalTags: (_, { template }) => template.id,
                transactionalTagsSaved: () => null,
            },
        ],
    })),
    selectors({
        filteredTransactionalTemplates: [
            (s) => [s.transactionalTemplates, s.filters],
            (templates: MessageTemplate[], filters: TransactionalEmailsFilters): MessageTemplate[] =>
                filterMessageTemplates(templates, filters),
        ],
        isFiltered: [
            (s) => [s.filters],
            (filters: TransactionalEmailsFilters): boolean => !objectsEqual(filters, DEFAULT_FILTERS),
        ],
    }),
    listeners(({ actions }) => ({
        saveTransactionalTags: async ({ template, tags }) => {
            try {
                await saveTemplateTags(template, tags)
            } catch (error: any) {
                lemonToast.error(`Couldn't save tags: ${error?.detail || error?.message || 'unknown error'}`)
            } finally {
                actions.transactionalTagsSaved()
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setFilters: () => {
            const { search, createdBy, tags } = values.filters
            const searchParams = {
                ...router.values.searchParams,
                search: search || undefined,
                created_by: createdBy ?? undefined,
                tags: tags.length ? tags : undefined,
            }
            return [router.values.location.pathname, searchParams, router.values.hashParams, { replace: true }]
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.transactional()]: (_, searchParams) => {
            // An in-app link back to the list, such as the breadcrumb out of an email, carries no filter
            // params. Parsing that URL would clear every filter, so the filters held in state are restored
            // and written back into the URL instead.
            if (!FILTER_URL_PARAMS.some((param) => param in searchParams)) {
                if (!objectsEqual(values.filters, DEFAULT_FILTERS)) {
                    actions.setFilters(values.filters)
                }
                return
            }
            const rawTags = searchParams['tags']
            const createdBy = parseInt(String(searchParams['created_by']))
            const parsed: TransactionalEmailsFilters = {
                search: searchParams['search'] ? String(searchParams['search']) : '',
                createdBy: Number.isNaN(createdBy) ? null : createdBy,
                // kea-router parses a JSON array in the URL back into an array.
                tags: Array.isArray(rawTags)
                    ? rawTags.map(String)
                    : typeof rawTags === 'string' && rawTags
                      ? [rawTags]
                      : [],
            }
            if (!objectsEqual(parsed, values.filters)) {
                actions.setFiltersFromUrl(parsed)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadTagsIfNeeded()
    }),
])
