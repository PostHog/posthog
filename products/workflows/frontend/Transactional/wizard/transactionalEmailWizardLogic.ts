export type transactionalEmailWizardLogicType = MakeLogicType<
    transactionalEmailWizardLogicValues,
    transactionalEmailWizardLogicActions,
    Record<string, any>,
    transactionalEmailWizardLogicMeta
>

export const transactionalEmailWizardLogic = kea<transactionalEmailWizardLogicType>([
    path(['products', 'workflows', 'frontend', 'Transactional', 'wizard', 'transactionalEmailWizardLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict'], integrationsLogic, ['integrations']],
    })),
    actions({
        setStep: (step: TransactionalEmailWizardStep) => ({ step }),
        nextStep: true,
        previousStep: true,
        updateDraft: (patch: Partial<TransactionalEmailDraft>) => ({ patch }),
        updateEmail: (patch: Partial<EmailTemplate>) => ({ patch }),
        addVariable: (name: string) => ({ name }),
        resetWizard: true,
        createTransactionalEmail: true,
        createTransactionalEmailFinished: (created: boolean) => ({ created }),
    }),
    reducers({
        currentStep: [
            'name' as TransactionalEmailWizardStep,
            {
                setStep: (_, { step }) => step,
                nextStep: (state) =>
                    TRANSACTIONAL_EMAIL_WIZARD_STEPS[
                        Math.min(
                            TRANSACTIONAL_EMAIL_WIZARD_STEPS.indexOf(state) + 1,
                            TRANSACTIONAL_EMAIL_WIZARD_STEPS.length - 1
                        )
                    ],
                previousStep: (state) =>
                    TRANSACTIONAL_EMAIL_WIZARD_STEPS[Math.max(TRANSACTIONAL_EMAIL_WIZARD_STEPS.indexOf(state) - 1, 0)],
                resetWizard: () => 'name',
            },
        ],
        draft: [
            EMPTY_DRAFT,
            {
                updateDraft: (state, { patch }) => ({ ...state, ...patch }),
                updateEmail: (state, { patch }) => ({ ...state, email: { ...state.email, ...patch } }),
                resetWizard: () => EMPTY_DRAFT,
            },
        ],
        // Variables added in the panel before the email uses them, so they can be inserted from the editor.
        addedVariables: [
            [] as string[],
            {
                addVariable: (state, { name }) => {
                    const cleaned = cleanVariableName(name)
                    return cleaned && !state.includes(cleaned) ? [...state, cleaned] : state
                },
                resetWizard: () => [],
            },
        ],
        isCreating: [
            false,
            {
                createTransactionalEmail: () => true,
                createTransactionalEmailFinished: () => false,
            },
        ],
        // Set once the template exists, so leaving the page no longer asks to discard it.
        created: [
            false,
            {
                createTransactionalEmailFinished: (_, { created }) => created,
                resetWizard: () => false,
            },
        ],
    }),
    selectors({
        senders: [
            (s) => [s.integrations],
            (integrations: IntegrationType[] | null): IntegrationType[] =>
                // make_transactional only accepts a verified sender.
                (integrations ?? []).filter(
                    (integration) => integration.kind === 'email' && integration.config?.verified === true
                ),
        ],
        stepErrors: [
            (s) => [s.draft, s.senders],
            (
                draft: TransactionalEmailDraft,
                senders: IntegrationType[]
            ): Record<TransactionalEmailWizardStep, string[]> => wizardStepErrors(draft, senders),
        ],
        currentStepErrors: [
            (s) => [s.stepErrors, s.currentStep],
            (stepErrors: Record<TransactionalEmailWizardStep, string[]>, currentStep: TransactionalEmailWizardStep) =>
                stepErrors[currentStep],
        ],
        variables: [(s) => [s.draft], (draft: TransactionalEmailDraft): string[] => variablesInEmail(draft.email)],
        // Everything the editor offers as a merge tag: what the email uses, plus what was added and not used yet.
        panelVariables: [
            (s) => [s.variables, s.addedVariables],
            (variables: string[], addedVariables: string[]): string[] => [
                ...variables,
                ...addedVariables.filter((name) => !variables.includes(name)),
            ],
        ],
        editorGlobals: [
            (s) => [s.panelVariables],
            (panelVariables: string[]): { variables: Record<string, string> } =>
                transactionalEditorGlobals(panelVariables),
        ],
        hasChanges: [(s) => [s.draft], (draft: TransactionalEmailDraft): boolean => draft !== EMPTY_DRAFT],
    }),
    listeners(({ actions, values }) => ({
        createTransactionalEmail: async () => {
            const firstInvalidStep = TRANSACTIONAL_EMAIL_WIZARD_STEPS.find((step) => values.stepErrors[step].length > 0)
            if (firstInvalidStep) {
                actions.setStep(firstInvalidStep)
                actions.createTransactionalEmailFinished(false)
                return
            }
            const { name, description, sensitive, email } = values.draft
            const teamId = String(values.currentTeamIdStrict)
            let templateId: string
            try {
                const template = await messagingTemplatesCreate(teamId, {
                    name: name.trim(),
                    description,
                    sensitive,
                    content: {
                        templating: 'liquid',
                        email: omitNullDesign(email),
                    } as unknown as MessageTemplateContentApi,
                })
                templateId = template.id
            } catch (error: any) {
                lemonToast.error(`Couldn't create the email: ${error?.detail ?? 'unknown error'}. Try again.`)
                actions.createTransactionalEmailFinished(false)
                return
            }
            try {
                await messagingTemplatesMakeTransactionalCreate(teamId, templateId, {})
                posthog.capture('transactional email created', { variable_count: values.variables.length, sensitive })
                lemonToast.success('Transactional email created')
            } catch (error: any) {
                // The template exists either way. Its API tab offers "Make transactional" to try again.
                posthog.capture('transactional email creation failed', { step: 'make_transactional' })
                lemonToast.error(
                    `Email saved, but it couldn't be made transactional: ${error?.detail ?? 'unknown error'}. Try again from its API tab.`
                )
            }
            actions.createTransactionalEmailFinished(true)
            router.actions.replace(urls.transactionalTemplate(templateId))
        },
        setStep: ({ step }) => {
            posthog.capture('transactional email wizard step viewed', { step })
        },
        nextStep: () => {
            posthog.capture('transactional email wizard step viewed', { step: values.currentStep })
        },
    })),
    afterMount(({ actions }) => {
        // Each visit to /transactional/new starts a new email.
        actions.resetWizard()
        posthog.capture('transactional email wizard step viewed', { step: 'name' })
    }),
    beforeUnload(({ values }) => ({
        enabled: () => values.hasChanges && !values.created,
        message: 'Leave this email?\nNothing is saved until you create it.',
    })),
])
