export type TransactionalEmailWizardStep = 'name' | 'sender' | 'content' | 'send'

export const TRANSACTIONAL_EMAIL_WIZARD_STEPS: TransactionalEmailWizardStep[] = ['name', 'sender', 'content', 'send']

export interface TransactionalEmailDraft {
    name: string
    description: string
    sensitive: boolean
    email: EmailTemplate
}

const EMPTY_DRAFT: TransactionalEmailDraft = {
    name: '',
    description: '',
    sensitive: false,
    // The editor's starter design, with no subject, so nothing sends as "Hello from PostHog" by accident.
    email: { ...NEW_TEMPLATE.content.email, subject: '' },
}

/** What still blocks each step, so Next and the stepper can say why. */
export function wizardStepErrors(
    draft: TransactionalEmailDraft,
    senders: IntegrationType[]
): Record<TransactionalEmailWizardStep, string[]> {
    const from = senderFrom(draft.email)
    const sender = senders.find((candidate) => candidate.id === from.integrationId)
    const addressError = senderAddressError(from.email, sender)
    return {
        name: draft.name.trim() ? [] : ['Give the email a name'],
        sender: !sender ? ['Choose who the email comes from'] : addressError ? [addressError] : [],
        content: [
            ...(draft.email.subject.trim() ? [] : ['Add a subject']),
            ...(draft.email.html || draft.email.text ? [] : ['Add a body']),
        ],
        send: [],
    }
}

