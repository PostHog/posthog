import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'

import type { CodeEmailApi } from 'products/messaging/frontend/generated/api.schemas'

import { listCodeEmails } from '../listCodeEmails'
import { transactionalEmailsLogic } from '../transactionalEmailsLogic'

export type SendFromCodeSurface = 'transactional' | 'transactional_guide' | 'email_domain' | 'workflows_onboarding'

export interface FirstCodeSendLogicProps {
    surface: SendFromCodeSurface
}

export type FirstCodeSend =
    | { status: 'unknown' }
    | { status: 'already_sending' }
    | { status: 'waiting' }
    | { status: 'arrived'; codeEmail: CodeEmailApi }

const MINUTE = 60_000
const POLL_FAST_MS = 10_000
const POLL_FAST_WINDOW_MS = 5 * MINUTE
const POLL_SLOW_MS = 30_000
const POLL_MAX_MS = 30 * MINUTE

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstCodeSendLogicValues {
    currentTeamId: number | null // teamLogic
    codeEmails: CodeEmailApi[] | null
    codeEmailsLoading: boolean
    firstCodeSend: FirstCodeSend
    pollingStartedAt: number | null
    pollingStopped: boolean
    sentBeforeMount: boolean | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstCodeSendLogicActions {
    checkAgain: () => {
        value: true
    }
    loadCodeEmails: () => any
    loadCodeEmailsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadCodeEmailsSuccess: (
        codeEmails: CodeEmailApi[],
        payload?: any
    ) => {
        codeEmails: CodeEmailApi[]
        payload?: any
    }
    schedulePoll: () => {
        value: true
    }
    startPolling: () => {
        value: true
    }
    stopPolling: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface firstCodeSendLogicMeta {
    key: any
    __keaTypeGenInternalSelectorTypes: {
        firstCodeSend: (codeEmails: any, sentBeforeMount: any) => FirstCodeSend
    }
}

export type firstCodeSendLogicType = MakeLogicType<
    firstCodeSendLogicValues,
    firstCodeSendLogicActions,
    FirstCodeSendLogicProps,
    firstCodeSendLogicMeta
>

export const firstCodeSendLogic = kea<firstCodeSendLogicType>([
    props({} as FirstCodeSendLogicProps),
    key((props) => props.surface),
    path((key) => ['products', 'workflows', 'frontend', 'Transactional', 'sendFromCode', 'firstCodeSendLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        startPolling: true,
        schedulePoll: true,
        stopPolling: true,
        checkAgain: true,
    }),
    loaders(({ values }) => ({
        codeEmails: [
            null as CodeEmailApi[] | null,
            {
                loadCodeEmails: async () => listCodeEmails(String(values.currentTeamId)),
            },
        ],
    })),
    reducers({
        sentBeforeMount: [
            null as boolean | null,
            {
                loadCodeEmailsSuccess: (state, { codeEmails }) => state ?? codeEmails.length > 0,
            },
        ],
        pollingStartedAt: [
            null as number | null,
            {
                startPolling: () => Date.now(),
            },
        ],
        pollingStopped: [
            false,
            {
                stopPolling: () => true,
                startPolling: () => false,
            },
        ],
    }),
    selectors({
        firstCodeSend: [
            (s) => [s.codeEmails, s.sentBeforeMount],
            (codeEmails: CodeEmailApi[] | null, sentBeforeMount: boolean | null): FirstCodeSend => {
                if (sentBeforeMount === null) {
                    return { status: 'unknown' }
                }
                if (sentBeforeMount) {
                    return { status: 'already_sending' }
                }
                const [codeEmail] = [...(codeEmails ?? [])].sort((a, b) => a.created_at.localeCompare(b.created_at))
                return codeEmail ? { status: 'arrived', codeEmail } : { status: 'waiting' }
            },
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        loadCodeEmailsSuccess: () => {
            const { firstCodeSend } = values
            if (firstCodeSend.status === 'arrived') {
                // pinned: analytics event name
                posthog.capture('first code send arrived', { surface: props.surface })
                transactionalEmailsLogic.findMounted()?.actions.loadCodeEmails()
            }
            if (firstCodeSend.status === 'waiting') {
                actions.schedulePoll()
            }
        },
        loadCodeEmailsFailure: () => {
            if (values.sentBeforeMount !== true) {
                actions.schedulePoll()
            }
        },
        schedulePoll: () => {
            const elapsed = Date.now() - (values.pollingStartedAt ?? Date.now())
            if (elapsed >= POLL_MAX_MS) {
                actions.stopPolling()
                return
            }
            const delay = elapsed < POLL_FAST_WINDOW_MS ? POLL_FAST_MS : POLL_SLOW_MS
            cache.disposables.add(() => {
                const timer = window.setTimeout(() => actions.loadCodeEmails(), delay)
                return () => clearTimeout(timer)
            }, 'poll')
        },
        checkAgain: () => {
            actions.startPolling()
            actions.loadCodeEmails()
        },
    })),
    afterMount(({ actions }) => {
        actions.startPolling()
        actions.loadCodeEmails()
    }),
])
