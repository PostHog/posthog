export const firstCodeSendLogic = kea<firstCodeSendLogicType>([
    props({} as FirstCodeSendLogicProps),
    key((props) => props.surface),
    path((key) => ['products', 'workflows', 'frontend', 'Transactional', 'sendFromCode', 'firstCodeSendLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        startPolling: true,
        schedulePoll: true,
        stopPolling: true,
        checkAgain: true,
        setSentBeforeMount: (sentBeforeMount: boolean) => ({ sentBeforeMount }),
    }),
    loaders(({ values }) => ({
        codeEmails: [
            null as CodeEmailApi[] | null,
            {
                checkForFirstCodeSend: async () => listCodeEmails(String(values.currentTeamId)),
            },
        ],
    })),
    reducers({
        sentBeforeMount: [
            null as boolean | null,
            {
                setSentBeforeMount: (_, { sentBeforeMount }) => sentBeforeMount,
            },
        ],
        lastCheckFailed: [
            false,
            {
                checkForFirstCodeSendSuccess: () => false,
                checkForFirstCodeSendFailure: () => true,
            },
        ],
        pollingStartedAt: [
            null as number | null,
            {
                startPolling: () => Date.now(),
            },
        ],
        pollingStopped: [
            false,
            {
                stopPolling: () => true,
                startPolling: () => false,
            },
        ],
    }),
    selectors({
        firstCodeSend: [
            (s) => [s.codeEmails, s.sentBeforeMount],
            (codeEmails: CodeEmailApi[] | null, sentBeforeMount: boolean | null): FirstCodeSend => {
                if (sentBeforeMount === null) {
                    return { status: 'unknown' }
                }
                if (sentBeforeMount) {
                    return { status: 'already_sending' }
                }
                const [codeEmail] = [...(codeEmails ?? [])].sort((a, b) => a.created_at.localeCompare(b.created_at))
                return codeEmail ? { status: 'arrived', codeEmail } : { status: 'waiting' }
            },
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        checkForFirstCodeSendSuccess: ({ codeEmails }) => {
            if (values.sentBeforeMount === null) {
                // After a failed first check, a send may have landed before this one, so only older emails count.
                actions.setSentBeforeMount(
                    cache.baselineMissed
                        ? codeEmails.some((codeEmail) => Date.parse(codeEmail.created_at) < cache.mountedAt)
                        : codeEmails.length > 0
                )
            }
            const { firstCodeSend } = values
            if (firstCodeSend.status === 'arrived' || firstCodeSend.status === 'already_sending') {
                cache.disposables.dispose('poll')
            }
            if (firstCodeSend.status === 'arrived') {
                // pinned: analytics event name
                posthog.capture('first code send arrived', { surface: props.surface })
            }
            if (firstCodeSend.status === 'waiting') {
                actions.schedulePoll()
            }
        },
        checkForFirstCodeSendFailure: () => {
            if (values.sentBeforeMount === null) {
                cache.baselineMissed = true
            }
            if (values.sentBeforeMount !== true) {
                actions.schedulePoll()
            }
        },
        schedulePoll: () => {
            const elapsed = Date.now() - (values.pollingStartedAt ?? Date.now())
            if (elapsed >= POLL_MAX_MS) {
                cache.disposables.dispose('poll')
                actions.stopPolling()
                return
            }
            const delay = elapsed < POLL_FAST_WINDOW_MS ? POLL_FAST_MS : POLL_SLOW_MS
            cache.disposables.add(() => {
                const timer = window.setTimeout(() => actions.checkForFirstCodeSend(), delay)
                return () => clearTimeout(timer)
            }, 'poll')
        },
        checkAgain: () => {
            actions.startPolling()
            actions.checkForFirstCodeSend()
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.mountedAt = Date.now()
        // The tab already loaded its list, so a failed first check must not lose that baseline.
        const tabCodeEmails = transactionalEmailsLogic.findMounted()?.values.codeEmails
        if (tabCodeEmails) {
            actions.setSentBeforeMount(tabCodeEmails.length > 0)
        }
        actions.startPolling()
        actions.checkForFirstCodeSend()
    }),
])
