import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { ApiError } from 'lib/api-error'
import { lemonToast } from 'lib/lemon-ui/LemonToast'
import {
    MAX_UPLOAD_BYTES,
    RESIZE_FAILED_MESSAGE,
    shrinkToUploadLimit,
} from 'scenes/hog-functions/email-templater/emailMediaLibrary'
import { teamLogic } from 'scenes/teamLogic'

import { uploadedMediaCreate, uploadedMediaList } from '~/generated/core/api'
import { UploadedMediaListPurpose } from '~/generated/core/api.schemas'
import type { UploadedMediaApi, UploadedMediaCreatedApi } from '~/generated/core/api.schemas'

const LIBRARY_PAGE_SIZE = 50

export async function uploadEmailImage(projectId: string, image: File): Promise<UploadedMediaCreatedApi> {
    let imageToUpload = image
    if (image.size > MAX_UPLOAD_BYTES) {
        try {
            imageToUpload = await shrinkToUploadLimit(image)
        } catch {
            posthog.capture('email media library image uploaded', { success: false, error_code: 'resize_failed' })
            throw new Error(RESIZE_FAILED_MESSAGE)
        }
    }
    try {
        const media = await uploadedMediaCreate(projectId, {
            image: imageToUpload,
            purpose: UploadedMediaListPurpose.Email,
        })
        // pinned: analytics event name and properties, renaming breaks dashboards
        posthog.capture('email media library image uploaded', { success: true, resized: imageToUpload !== image })
        return media
    } catch (error) {
        posthog.capture('email media library image uploaded', {
            success: false,
            error_code: error instanceof ApiError ? (error.code ?? error.status) : null,
        })
        throw error
    }
}

export function uploadErrorText(error: unknown): string {
    if (error instanceof ApiError) {
        return error.detail || "Couldn't upload this image. Try again."
    }
    return error instanceof Error && error.message === RESIZE_FAILED_MESSAGE
        ? RESIZE_FAILED_MESSAGE
        : "Couldn't upload this image. Try again."
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface emailMediaLibraryLogicValues {
    currentProjectId: number | string // teamLogic
    images: UploadedMediaApi[] | null
    imagesLoading: boolean
    search: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface emailMediaLibraryLogicActions {
    loadImages: (_: void) => void
    loadImagesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadImagesSuccess: (
        images: UploadedMediaApi[],
        payload?: void
    ) => {
        images: UploadedMediaApi[]
        payload?: void
    }
    setSearch: (search: string) => {
        search: string
    }
}

export type emailMediaLibraryLogicType = MakeLogicType<emailMediaLibraryLogicValues, emailMediaLibraryLogicActions>

export const emailMediaLibraryLogic = kea<emailMediaLibraryLogicType>([
    path(['products', 'workflows', 'frontend', 'EmailDocumentEditor', 'emailMediaLibraryLogic']),
    connect(() => ({ values: [teamLogic, ['currentProjectId']] })),
    actions({
        setSearch: (search: string) => ({ search }),
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
    }),
    loaders(({ values }) => ({
        images: [
            null as UploadedMediaApi[] | null,
            {
                loadImages: async (_: void, breakpoint) => {
                    await breakpoint(200)
                    posthog.capture('email media library viewed', { searched: !!values.search })
                    const response = await uploadedMediaList(String(values.currentProjectId), {
                        purpose: UploadedMediaListPurpose.Email,
                        limit: LIBRARY_PAGE_SIZE,
                        search: values.search.trim() || undefined,
                    })
                    return response.results
                },
            },
        ],
    })),
    listeners(({ actions }) => ({
        setSearch: () => actions.loadImages(),
        loadImagesFailure: () => {
            lemonToast.error("Couldn't load your images. Try again.")
        },
    })),
])
