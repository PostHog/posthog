export const channelCatalogLogic = kea<channelCatalogLogicType>([
    path(['products', 'workflows', 'frontend', 'Channels', 'channelCatalogLogic']),
    connect(() => ({
        values: [
            integrationsLogic,
            [
                'integrations',
                'integrationsLoadError',
                'integrationsLoadFailed',
                'integrationsLoading',
                'sandboxEmailSender',
                'sandboxEmailSenderEnabled',
            ],
            featureFlagLogic,
            ['featureFlags'],
            teamLogic,
            ['currentProjectId'],
        ],
        actions: [integrationsLogic, ['openSetupModal', 'loadIntegrations'], featureFlagLogic, ['setFeatureFlags']],
    })),
    actions({
        startChannelSetup: (kind: ChannelType) => ({ kind }),
        retrySandboxSenderSetup: true,
    }),
    loaders(({ actions, values }) => ({
        // The endpoint is idempotent, so the page asks for the sandbox sender on every visit.
        sandboxProvisionError: [
            null as string | null,
            {
                setUpSandboxSender: async (_, breakpoint): Promise<string | null> => {
                    let failure: string | null = null
                    try {
                        await integrationsEmailSandboxSenderCreate(String(values.currentProjectId))
                    } catch (error) {
                        failure = (error instanceof ApiError && error.detail) || 'Could not set up the sandbox sender.'
                    }
                    breakpoint()
                    if (!failure) {
                        actions.loadIntegrations()
                    }
                    return failure
                },
            },
        ],
    })),
    selectors({
        sandboxSetupLoading: [
            (s) => [s.integrationsLoading, s.sandboxProvisionErrorLoading],
            (loading: boolean, provisioning: boolean): boolean => loading || provisioning,
        ],
        sandboxSetupError: [
            (s) => [s.integrationsLoadFailed, s.sandboxProvisionError],
            (loadFailed: boolean, setupError: string | null): string | null => (loadFailed ? null : setupError),
        ],
        /** `null` until the integrations load, so the catalog never shows a channel as not set up by mistake. */
        channels: [
            (s) => [s.integrations, s.featureFlags],
            (integrations: IntegrationType[] | null, featureFlags: FeatureFlagsSet): ChannelSummary[] | null =>
                integrations === null
                    ? null
                    : CATALOG_CHANNELS.filter(
                          (kind) =>
                              !PUSH_CHANNELS.includes(kind) ||
                              !!featureFlags[FEATURE_FLAGS.WORKFLOWS_PUSH_NOTIFICATIONS]
                      ).map((kind) => summarizeChannel(kind, integrations)),
        ],
        activeCount: [
            (s) => [s.channels],
            (channels: ChannelSummary[] | null): number =>
                channels?.filter((channel) => channel.status === 'active').length ?? 0,
        ],
    }),
    listeners(({ actions, values }) => ({
        setFeatureFlags: () => {
            if (
                values.sandboxEmailSenderEnabled &&
                !values.sandboxEmailSender &&
                !values.sandboxProvisionErrorLoading
            ) {
                actions.setUpSandboxSender()
            }
        },
        retrySandboxSenderSetup: () => {
            if (values.sandboxSetupLoading) {
                return
            }
            actions.loadIntegrations()
            if (values.sandboxEmailSenderEnabled) {
                actions.setUpSandboxSender()
            }
        },
        startChannelSetup: ({ kind }) => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows channel setup started', {
                kind,
                status: values.channels?.find((channel) => channel.kind === kind)?.status,
            })
            if (kind === 'slack') {
                // Slack connects through OAuth on slack.com, so `next` returns the person to the tab they left.
                window.location.href = api.integrations.authorizeUrl({
                    kind: 'slack',
                    next: removeProjectIdIfPresent(router.values.location.pathname),
                })
                return
            }
            if (kind === 'email' && values.featureFlags[FEATURE_FLAGS.WORKFLOWS_EMAIL_DOMAIN_WIZARD]) {
                openEmailDomainSetupPage('channels')
                return
            }
            actions.openSetupModal(undefined, kind)
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.sandboxEmailSenderEnabled) {
            actions.setUpSandboxSender()
        }
    }),
])
