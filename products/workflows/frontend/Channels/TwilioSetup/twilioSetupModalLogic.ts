export type twilioSetupModalLogicType = MakeLogicType<
    twilioSetupModalLogicValues,
    twilioSetupModalLogicActions,
    TwilioSetupModalLogicProps
>

export const twilioSetupModalLogic = kea<twilioSetupModalLogicType>([
    path(['products', 'workflows', 'frontend', 'TwilioSetup', 'twilioSetupModalLogic']),
    props({} as TwilioSetupModalLogicProps),
    connect(() => ({
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    forms(({ props, actions, values }) => ({
        twilioIntegration: {
            defaults: {
                accountSid: '',
                authToken: '',
            },
            errors: ({ accountSid, authToken }) => ({
                accountSid: accountSid.trim() ? undefined : 'Account SID is required',
                authToken: authToken.trim() ? undefined : 'Auth Token is required',
            }),
            submit: async () => {
                try {
                    const integration = await api.integrations.create({
                        kind: 'twilio',
                        config: {
                            account_sid: values.twilioIntegration.accountSid,
                            auth_token: values.twilioIntegration.authToken,
                        },
                    })
                    actions.loadIntegrations()
                    lemonToast.success('Twilio channel created successfully!')
                    props.onComplete(integration.id)
                } catch (error: any) {
                    // A 400 means Twilio rejected the keys. Flag both fields, since Twilio does not
                    // say which one is wrong.
                    if (error.status === 400) {
                        actions.setTwilioIntegrationManualErrors({
                            accountSid: 'Rejected by Twilio',
                            authToken: 'Rejected by Twilio',
                        })
                    }
                    lemonToast.error(error.detail || 'Failed to create Twilio channel')
                    throw error
                }
            },
        },
    })),
    listeners(({ actions, values }) => ({
        setTwilioIntegrationValue: () => {
            // Kea Forms keeps manual errors until a field is touched, and includes them in the
            // form's error gate. A rejection flags both keys, so editing one field would leave the
            // other's error and block the next submit. Clear both as soon as either field changes.
            if (Object.keys(values.twilioIntegrationManualErrors).length > 0) {
                actions.setTwilioIntegrationManualErrors({})
            }
        },
    })),
])
