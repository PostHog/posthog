export type apnsSetupModalLogicType = MakeLogicType<
    apnsSetupModalLogicValues,
    apnsSetupModalLogicActions,
    APNSSetupModalLogicProps
>

export const apnsSetupModalLogic = kea<apnsSetupModalLogicType>([
    path(['products', 'workflows', 'frontend', 'APNSSetup', 'apnsSetupModalLogic']),
    props({} as APNSSetupModalLogicProps),
    connect(() => ({
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        setSigningKeyFiles: (files: File[]) => ({ files }),
        setSigningKeyFileError: (error: string | null) => ({ error }),
    }),
    reducers({
        signingKeyFileError: [
            null as string | null,
            {
                setSigningKeyFileError: (_, { error }) => error,
                setSigningKeyFiles: () => null,
            },
        ],
    }),
    listeners(({ actions }) => ({
        setSigningKeyFiles: async ({ files }, breakpoint) => {
            const file = files[0]
            if (!file) {
                return
            }
            let contents: string
            try {
                contents = await file.text()
            } catch {
                actions.setSigningKeyFileError("Couldn't read that file. Try again, or paste the key contents instead.")
                return
            }
            // Picking a second file while this read is in flight makes this result stale. Without the
            // breakpoint whichever read finished last would win, so an earlier file could overwrite the
            // key while the input shows the newer filename.
            breakpoint()
            if (!contents.includes(PEM_MARKER)) {
                actions.setSigningKeyFileError(
                    "That file doesn't look like a signing key. Upload the .p8 file you downloaded from Apple."
                )
                return
            }
            actions.setApnsIntegrationValue('signingKey', contents.trim())
        },
    })),
    forms(({ props, actions, values }) => ({
        apnsIntegration: {
            defaults: {
                signingKey: '',
                keyId: '',
                teamId: '',
                bundleId: '',
                environment: 'production' as const,
                identityVerification: resolvePushIdentityVerification(props.integration),
            },
            errors: ({ signingKey, keyId, teamId, bundleId }) => ({
                signingKey: signingKey.trim() ? undefined : 'Signing key is required',
                keyId: keyId.trim() ? undefined : 'Key ID is required',
                teamId: teamId.trim() ? undefined : 'Team ID is required',
                bundleId: bundleId.trim() ? undefined : 'Bundle ID is required',
            }),
            submit: async () => {
                try {
                    const integration = await api.integrations.create({
                        kind: 'apns',
                        config: {
                            signing_key: values.apnsIntegration.signingKey,
                            key_id: values.apnsIntegration.keyId,
                            team_id_apple: values.apnsIntegration.teamId,
                            bundle_id: values.apnsIntegration.bundleId,
                            environment: values.apnsIntegration.environment,
                            ...pushIdentityVerificationPayload(
                                values.apnsIntegration.identityVerification,
                                props.integration
                            ),
                        },
                    })
                    actions.loadIntegrations()
                    lemonToast.success('APNS channel created successfully!')
                    props.onComplete(integration.id)
                } catch (error: any) {
                    lemonToast.error(error.detail || 'Failed to create APNS channel')
                    throw error
                }
            },
        },
    })),
])
