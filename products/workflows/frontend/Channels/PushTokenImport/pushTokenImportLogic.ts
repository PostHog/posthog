export type pushTokenImportLogicType = MakeLogicType<
    pushTokenImportLogicValues,
    pushTokenImportLogicActions,
    Record<string, any>,
    pushTokenImportLogicMeta
>

export const pushTokenImportLogic = kea<pushTokenImportLogicType>([
    path(['products', 'workflows', 'frontend', 'Channels', 'PushTokenImport', 'pushTokenImportLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        openImport: (integration: IntegrationType) => ({ integration }),
        closeImport: true,
        latestLoaded: true,
        setFile: (file: File | null) => ({ file }),
        setError: (error: string | null) => ({ error }),
        startImport: true,
        importUnknownPersons: true,
        importStarted: (job: PushTokenImportApi) => ({ job }),
        importUpdated: (job: PushTokenImportApi) => ({ job }),
        requestFailed: (error: string) => ({ error }),
        stopImport: true,
        pollImport: true,
        importAnotherFile: true,
    }),
    reducers({
        integration: [
            null as IntegrationType | null,
            {
                openImport: (_, { integration }) => integration,
                closeImport: () => null,
            },
        ],
        loadingLatest: [
            false,
            {
                openImport: () => true,
                latestLoaded: () => false,
            },
        ],
        file: [
            null as File | null,
            {
                setFile: (_, { file }) => file,
                openImport: () => null,
                importStarted: () => null,
                importAnotherFile: () => null,
            },
        ],
        currentImport: [
            null as PushTokenImportApi | null,
            {
                importStarted: (_, { job }) => job,
                importUpdated: (_, { job }) => job,
                openImport: () => null,
                importAnotherFile: () => null,
            },
        ],
        error: [
            null as string | null,
            {
                setError: (_, { error }) => error,
                requestFailed: (_, { error }) => error,
                setFile: () => null,
                openImport: () => null,
                startImport: () => null,
                importStarted: () => null,
                importAnotherFile: () => null,
            },
        ],
        submitting: [
            false,
            {
                startImport: () => true,
                importUnknownPersons: () => true,
                importStarted: () => false,
                requestFailed: () => false,
                openImport: () => false,
            },
        ],
        stopping: [
            false,
            {
                stopImport: () => true,
                importUpdated: (state, { job }) => state && isActive(job),
                requestFailed: () => false,
                openImport: () => false,
            },
        ],
    }),
    selectors({
        isOpen: [(s) => [s.integration], (integration: IntegrationType | null): boolean => integration !== null],
        isRunning: [
            (s) => [s.currentImport],
            (currentImport: PushTokenImportApi | null): boolean => !!currentImport && isActive(currentImport),
        ],
        isStopping: [
            (s) => [s.stopping, s.currentImport],
            (stopping: boolean, currentImport: PushTokenImportApi | null): boolean =>
                stopping || currentImport?.status === PushTokenImportStatusEnumApi.Cancelled,
        ],
        startDisabledReason: [
            (s) => [s.file, s.error, s.submitting, s.currentProjectId],
            (file: File | null, error: string | null, submitting: boolean, currentProjectId: number | null) => {
                if (submitting) {
                    return 'Uploading the file'
                }
                if (currentProjectId === null) {
                    return "Couldn't find the project. Reload the page and try again."
                }
                if (!file) {
                    return 'Choose a CSV file'
                }
                if (error) {
                    return 'Fix the file and choose it again'
                }
                return null
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        openImport: async ({ integration }) => {
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('workflows push token import opened', { channel_kind: integration.kind })
            try {
                const { latest } = await pushTokenImportsLatestRetrieve(String(values.currentProjectId), {
                    integration_id: integration.id,
                })
                if (latest && values.integration?.id === integration.id && isRecent(latest)) {
                    actions.importUpdated(latest)
                    if (isActive(latest)) {
                        actions.pollImport()
                    }
                }
            } catch {
                // Without the last result the dialog still lets the user upload a file.
            }
            actions.latestLoaded()
        },
        setFile: ({ file }) => {
            if (file && file.size > MAX_FILE_BYTES) {
                actions.setError(
                    `This file is larger than ${MAX_FILE_BYTES / 1024 / 1024} MB. Split it into smaller files and import them one at a time.`
                )
            }
        },
        startImport: async () => {
            const { integration, file, currentProjectId } = values
            if (!integration || !file || currentProjectId === null) {
                return
            }
            try {
                const job = await pushTokenImportsCreate(String(currentProjectId), {
                    integration_id: integration.id,
                    device_token_file: file,
                })
                // The dialog moved to another channel while the file uploaded.
                if (values.integration?.id !== integration.id) {
                    return
                }
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows push token import started', {
                    channel_kind: integration.kind,
                    rows: job.total_devices,
                    bytes: file.size,
                    create_missing_persons: false,
                })
                actions.importStarted(job)
                actions.pollImport()
            } catch (error: any) {
                actions.requestFailed(errorMessage(error, "Couldn't upload the file. Try again."))
            }
        },
        importUnknownPersons: async () => {
            const { integration, currentImport, currentProjectId } = values
            if (!integration || !currentImport || currentProjectId === null) {
                return
            }
            try {
                const job = await pushTokenImportsImportUnknownPersonsCreate(String(currentProjectId), currentImport.id)
                if (values.integration?.id !== integration.id) {
                    return
                }
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflows push token import started', {
                    channel_kind: integration.kind,
                    rows: job.total_devices,
                    create_missing_persons: true,
                })
                actions.importStarted(job)
                actions.pollImport()
            } catch (error: any) {
                actions.requestFailed(errorMessage(error, "Couldn't start the import. Try again."))
            }
        },
        stopImport: async () => {
            const { currentImport, currentProjectId } = values
            if (!currentImport || currentProjectId === null) {
                return
            }
            try {
                const job = await pushTokenImportsCancelCreate(String(currentProjectId), currentImport.id)
                actions.importUpdated(job)
                if (isActive(job)) {
                    actions.pollImport()
                }
            } catch (error: any) {
                actions.requestFailed(errorMessage(error, "Couldn't stop the import. Try again."))
            }
        },
        pollImport: async (_, breakpoint) => {
            await breakpoint(POLL_INTERVAL_MS)
            const { currentImport, currentProjectId } = values
            if (!values.isOpen || !currentImport || currentProjectId === null) {
                return
            }
            let job = currentImport
            try {
                job = await pushTokenImportsRetrieve(String(currentProjectId), currentImport.id)
            } catch (error: any) {
                if (error?.status === 403 || error?.status === 404) {
                    actions.requestFailed(errorMessage(error, "Couldn't read the import."))
                    return
                }
            }
            breakpoint()
            if (values.currentImport?.id !== job.id) {
                return
            }
            actions.importUpdated(job)
            if (isActive(job)) {
                actions.pollImport()
            }
        },
    })),
])
