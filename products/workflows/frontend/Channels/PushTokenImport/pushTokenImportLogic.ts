export const pushTokenImportLogic = kea<pushTokenImportLogicType>([
    path(['products', 'workflows', 'frontend', 'Channels', 'PushTokenImport', 'pushTokenImportLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        openImport: (integration: IntegrationType) => ({ integration }),
        closeImport: true,
        setFile: (file: File | null) => ({ file }),
        fileParsed: (parsed: ParsedPushTokenCsv | null, error: string | null) => ({ parsed, error }),
        startImport: true,
        importUnknownPersons: true,
        stopImport: true,
        setProgress: (rowsDone: number, imported: number, total: number) => ({ rowsDone, imported, total }),
        importFinished: (outcome: PushTokenImportOutcome) => ({ outcome }),
    }),
    reducers({
        integration: [
            null as IntegrationType | null,
            {
                openImport: (_, { integration }) => integration,
                closeImport: () => null,
            },
        ],
        file: [
            null as File | null,
            {
                setFile: (_, { file }) => file,
                openImport: () => null,
            },
        ],
        parsed: [
            null as ParsedPushTokenCsv | null,
            {
                fileParsed: (_, { parsed }) => parsed,
                setFile: () => null,
                openImport: () => null,
            },
        ],
        parseError: [
            null as string | null,
            {
                fileParsed: (_, { error }) => error,
                setFile: () => null,
                openImport: () => null,
            },
        ],
        importing: [
            false,
            {
                startImport: () => true,
                importUnknownPersons: () => true,
                importFinished: () => false,
            },
        ],
        stopping: [
            false,
            {
                stopImport: () => true,
                startImport: () => false,
                importUnknownPersons: () => false,
                importFinished: () => false,
            },
        ],
        progress: [
            { rowsDone: 0, imported: 0, total: 0 },
            {
                setProgress: (_, progress) => progress,
            },
        ],
        outcome: [
            null as PushTokenImportOutcome | null,
            {
                importFinished: (_, { outcome }) => outcome,
                setFile: () => null,
                openImport: () => null,
                startImport: () => null,
            },
        ],
    }),
    selectors({
        isOpen: [(s) => [s.integration], (integration: IntegrationType | null): boolean => integration !== null],
        rowCount: [(s) => [s.parsed], (parsed: ParsedPushTokenCsv | null): number => parsed?.rows.length ?? 0],
        /** Every line of the file that was not stored: skipped before sending, or refused by the API. */
        failedRows: [
            (s) => [s.parsed, s.outcome],
            (parsed: ParsedPushTokenCsv | null, outcome: PushTokenImportOutcome | null): FailedPushTokenRow[] =>
                [...(parsed?.rejected ?? []), ...(outcome?.failed ?? [])].sort((a, b) => a.line - b.line),
        ],
        unknownPersonRows: [
            (s) => [s.outcome],
            (outcome: PushTokenImportOutcome | null): FailedPushTokenRow[] =>
                outcome?.failed.filter((row) => row.unknownPerson) ?? [],
        ],
        startDisabledReason: [
            (s) => [s.file, s.parsed, s.parseError, s.importing, s.currentProjectId],
            (
                file: File | null,
                parsed: ParsedPushTokenCsv | null,
                parseError: string | null,
                importing: boolean,
                currentProjectId: number | null
            ): string | null => {
                if (importing) {
                    return 'Importing devices'
                }
                if (currentProjectId === null) {
                    return "Couldn't find the project. Reload the page and try again."
                }
                if (!file) {
                    return 'Choose a CSV file'
                }
                if (parseError) {
                    return 'Fix the file and choose it again'
                }
                if (!parsed) {
                    return 'Reading the file'
                }
                if (parsed.rows.length === 0) {
                    return 'The file has no devices that can be imported'
                }
                return null
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const runImport = async (
            rows: PushTokenRow[],
            createMissingPersons: boolean
        ): Promise<PushTokenImportOutcome | null> => {
            const { integration, currentProjectId } = values
            // The button is disabled while an import runs, but a second dispatch must not start a parallel import.
            if (cache.importInFlight || !integration || currentProjectId === null) {
                return null
            }
            cache.importInFlight = true
            const stop = new AbortController()
            cache.stop = stop
            const tracked = {
                channel_kind: integration.kind,
                rows: rows.length,
                requests: chunkRows(rows).length,
                create_missing_persons: createMissingPersons,
            }
            posthog.capture('workflows push token import started', tracked)
            actions.setProgress(0, 0, rows.length)
            const outcome = await runPushTokenImport({
                rows,
                createMissingPersons,
                send: (subscriptions, options, signal) =>
                    integrationsPushTokensCreate(
                        String(currentProjectId),
                        integration.id,
                        { subscriptions, ...options },
                        { signal }
                    ),
                sleep: sleepUnlessAborted,
                onChunkDone: (rowsDone, imported) => actions.setProgress(rowsDone, imported, rows.length),
                stop: stop.signal,
            })
            cache.importInFlight = false
            posthog.capture('workflows push token import finished', {
                ...tracked,
                imported: outcome.imported,
                failed: outcome.failed.length,
                unknown_persons: outcome.failed.filter((row) => row.unknownPerson).length,
                stopped_reason: outcome.stoppedReason,
            })
            return outcome
        }

        return {
            openImport: ({ integration }) => {
                posthog.capture('workflows push token import opened', { channel_kind: integration.kind })
            },
            setFile: async ({ file }) => {
                if (!file) {
                    return
                }
                if (file.size > MAX_FILE_BYTES) {
                    const message = `This file is larger than ${MAX_FILE_BYTES / 1024 / 1024} MB. Split it into smaller files and import them one at a time.`
                    posthog.capture('workflows push token import file parsed', {
                        error: 'file_too_large',
                        bytes: file.size,
                    })
                    actions.fileParsed(null, message)
                    return
                }
                let parsed: ParsedPushTokenCsv
                try {
                    parsed = parsePushTokenCsv(await readCsvText(file))
                } catch (error: any) {
                    // A newer file replaced this one while it was read.
                    if (values.file !== file) {
                        return
                    }
                    const message = error?.message ?? "Couldn't read the file."
                    posthog.capture('workflows push token import file parsed', { error: message })
                    actions.fileParsed(null, message)
                    return
                }
                if (values.file !== file) {
                    return
                }
                posthog.capture('workflows push token import file parsed', {
                    rows: parsed.rows.length,
                    rejected: parsed.rejected.length,
                    duplicates: parsed.duplicates,
                })
                actions.fileParsed(parsed, null)
            },
            startImport: async () => {
                if (!values.parsed) {
                    return
                }
                const outcome = await runImport(values.parsed.rows, false)
                if (outcome) {
                    actions.importFinished(outcome)
                }
            },
            importUnknownPersons: async () => {
                const previous = values.outcome
                const rows = values.unknownPersonRows.map(({ line, distinct_id, device_token }) => ({
                    line,
                    distinct_id,
                    device_token,
                }))
                if (!previous || rows.length === 0) {
                    return
                }
                const outcome = await runImport(rows, true)
                if (outcome) {
                    actions.importFinished({
                        imported: previous.imported + outcome.imported,
                        failed: [...previous.failed.filter((row) => !row.unknownPerson), ...outcome.failed],
                        stoppedReason: outcome.stoppedReason,
                    })
                }
            },
            stopImport: () => {
                cache.stop?.abort()
            },
            closeImport: () => {
                cache.stop?.abort()
            },
        }
    }),
    beforeUnload(({ values, actions }) => ({
        enabled: () => values.importing,
        message: 'Leave this page?\nThe import stops, and devices not sent yet are not imported.',
        onConfirm: () => actions.stopImport(),
    })),
    beforeUnmount(({ cache }) => {
        cache.stop?.abort()
    }),
])
