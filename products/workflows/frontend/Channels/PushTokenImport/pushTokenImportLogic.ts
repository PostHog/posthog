import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { projectLogic } from 'scenes/projectLogic'

import type { IntegrationType } from '~/types'

import {
    pushTokenImportsCancelCreate,
    pushTokenImportsCreate,
    pushTokenImportsImportUnknownPersonsCreate,
    pushTokenImportsLatestRetrieve,
    pushTokenImportsRetrieve,
} from 'products/workflows/frontend/generated/api'
import type { PushTokenImportApi } from 'products/workflows/frontend/generated/api.schemas'
import { PushTokenImportStatusEnumApi } from 'products/workflows/frontend/generated/api.schemas'

// The server refuses larger files, so checking here saves uploading one.
export const MAX_FILE_BYTES = 20 * 1024 * 1024
const POLL_INTERVAL_MS = 2000
// A result this recent is shown again when the dialog reopens, so closing it during an import loses nothing.
const RECENT_RESULT_MS = 24 * 60 * 60 * 1000

function errorMessage(error: any, fallback: string): string {
    return error?.detail ?? error?.data?.detail ?? error?.message ?? fallback
}

/** A stopped import is still sending its last batch until the server sets `finished_at`. */
function isActive(job: PushTokenImportApi): boolean {
    return job.status === PushTokenImportStatusEnumApi.Running || !job.finished_at
}

function isRecent(job: PushTokenImportApi): boolean {
    return isActive(job) || Date.now() - new Date(job.finished_at as string).getTime() < RECENT_RESULT_MS
}

