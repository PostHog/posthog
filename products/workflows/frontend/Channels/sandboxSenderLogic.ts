export const sandboxSenderLogic = kea<sandboxSenderLogicType>([
    path(['products', 'workflows', 'frontend', 'Channels', 'sandboxSenderLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        provisionSandboxSender: (surface: SandboxSenderSurface) => ({ surface }),
        provisionSandboxSenderFailed: (error: string) => ({ error }),
        setSandboxIntegrationId: (integrationId: number) => ({ integrationId }),
    }),
    loaders(({ values }) => ({
        sandboxStatus: [
            null as WorkflowEmailSandboxStatusApi | null,
            {
                loadSandboxStatus: async () =>
                    values.currentTeamId ? await workflowEmailSandboxStatus(String(values.currentTeamId)) : null,
            },
        ],
    })),
    reducers({
        sandboxStatus: {
            setSandboxIntegrationId: (status, { integrationId }) =>
                status ? { ...status, integration_id: integrationId } : status,
        },
        provisioning: [
            false,
            {
                provisionSandboxSender: () => true,
                setSandboxIntegrationId: () => false,
                provisionSandboxSenderFailed: () => false,
            },
        ],
        provisionError: [
            null as string | null,
            {
                provisionSandboxSender: () => null,
                provisionSandboxSenderFailed: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        canAdoptSandbox: [
            (s) => [s.sandboxStatus],
            (status: WorkflowEmailSandboxStatusApi | null): boolean => canAdoptSandboxSender(status),
        ],
        setupProblem: [
            (s) => [s.sandboxStatus, s.provisioning, s.provisionError],
            (
                status: WorkflowEmailSandboxStatusApi | null,
                provisioning: boolean,
                provisionError: string | null
            ): string | null =>
                provisionError ?? (status?.integration_id === null && !provisioning ? NOT_SET_UP : null),
        ],
    }),
    listeners(({ actions, values }) => ({
        provisionSandboxSender: async ({ surface }) => {
            try {
                actions.setSandboxIntegrationId(await provisionSandboxSender(String(values.currentTeamId), surface))
            } catch (error: any) {
                actions.provisionSandboxSenderFailed(error?.detail || PROVISION_FAILED)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSandboxStatus()
    }),
])
