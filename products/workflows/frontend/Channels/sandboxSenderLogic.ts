import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { workflowEmailSandboxStatus } from '../generated/api'
import type { WorkflowEmailSandboxStatusApi } from '../generated/api.schemas'
import { SandboxSenderSurface, canAdoptSandboxSender, provisionSandboxSender } from './sandboxSender'

const PROVISION_FAILED = "Couldn't set up the sandbox sender. Try again, or choose your own sender."
const NOT_SET_UP = "The sandbox sender isn't set up for this project yet."
const ORGANIZATION_BLOCKED = 'Sandbox email is turned off for your organization. Choose your own sender.'
const UNAVAILABLE = "The sandbox sender isn't available for this project. Choose your own sender."

export interface SandboxSetup {
    problem: string
    canSetUp: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sandboxSenderLogicValues {
    currentTeamId: number | null // teamLogic
    canAdoptSandbox: boolean
    provisionError: string | null
    provisioning: boolean
    sandboxSetup: SandboxSetup | null
    sandboxStatus: WorkflowEmailSandboxStatusApi | null
    sandboxStatusLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sandboxSenderLogicActions {
    loadSandboxStatus: () => any
    loadSandboxStatusFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSandboxStatusSuccess: (
        sandboxStatus: WorkflowEmailSandboxStatusApi | null,
        payload?: any
    ) => {
        sandboxStatus: WorkflowEmailSandboxStatusApi | null
        payload?: any
    }
    provisionSandboxSender: (surface: SandboxSenderSurface) => {
        surface: SandboxSenderSurface
    }
    provisionSandboxSenderFailed: (error: string) => {
        error: string
    }
    setSandboxIntegrationId: (integrationId: number) => {
        integrationId: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sandboxSenderLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        canAdoptSandbox: (sandboxStatus: WorkflowEmailSandboxStatusApi | null) => boolean
        sandboxSetup: (
            sandboxStatus: WorkflowEmailSandboxStatusApi | null,
            provisionError: string | null
        ) => SandboxSetup | null
    }
}

export type sandboxSenderLogicType = MakeLogicType<
    sandboxSenderLogicValues,
    sandboxSenderLogicActions,
    Record<string, any>,
    sandboxSenderLogicMeta
>

export const sandboxSenderLogic = kea<sandboxSenderLogicType>([
    path(['products', 'workflows', 'frontend', 'Channels', 'sandboxSenderLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        provisionSandboxSender: (surface: SandboxSenderSurface) => ({ surface }),
        provisionSandboxSenderFailed: (error: string) => ({ error }),
        setSandboxIntegrationId: (integrationId: number) => ({ integrationId }),
    }),
    loaders(({ values }) => ({
        sandboxStatus: [
            null as WorkflowEmailSandboxStatusApi | null,
            {
                loadSandboxStatus: async () =>
                    values.currentTeamId ? await workflowEmailSandboxStatus(String(values.currentTeamId)) : null,
            },
        ],
    })),
    reducers({
        sandboxStatus: {
            setSandboxIntegrationId: (status, { integrationId }) =>
                status ? { ...status, integration_id: integrationId } : status,
        },
        provisioning: [
            false,
            {
                provisionSandboxSender: () => true,
                setSandboxIntegrationId: () => false,
                provisionSandboxSenderFailed: () => false,
            },
        ],
        provisionError: [
            null as string | null,
            {
                provisionSandboxSender: () => null,
                provisionSandboxSenderFailed: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        canAdoptSandbox: [
            (s) => [s.sandboxStatus],
            (status: WorkflowEmailSandboxStatusApi | null): boolean => canAdoptSandboxSender(status),
        ],
        sandboxSetup: [
            (s) => [s.sandboxStatus, s.provisionError],
            (status: WorkflowEmailSandboxStatusApi | null, provisionError: string | null): SandboxSetup | null => {
                if (provisionError) {
                    return { problem: provisionError, canSetUp: true }
                }
                if (status?.organization_blocked) {
                    return { problem: ORGANIZATION_BLOCKED, canSetUp: false }
                }
                if (status?.integration_id !== null || !status) {
                    return null
                }
                return canAdoptSandboxSender(status)
                    ? { problem: NOT_SET_UP, canSetUp: true }
                    : { problem: UNAVAILABLE, canSetUp: false }
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        provisionSandboxSender: async ({ surface }) => {
            try {
                actions.setSandboxIntegrationId(await provisionSandboxSender(String(values.currentTeamId), surface))
            } catch (error: any) {
                actions.provisionSandboxSenderFailed(error?.detail || PROVISION_FAILED)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSandboxStatus()
    }),
])
