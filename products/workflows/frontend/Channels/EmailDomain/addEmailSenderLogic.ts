import { urls } from 'scenes/urls'

import { EmailIntegrationDomainGroupedType, IntegrationType } from '~/types'

import { integrationsCreate, integrationsEmailVerifyCreate } from 'products/integrations/frontend/generated/api'
import type { IntegrationConfigApi } from 'products/integrations/frontend/generated/api.schemas'

import { openEmailDomainSetupPage } from './useStartEmailDomainSetup'

export type AddEmailSenderEntry = 'catalog' | 'domain_row'

export interface AddedSender {
    sender: IntegrationConfigApi
    email: string
    domain: string
    existingSendersOnDomain: number
    verified: boolean
}

export interface SenderDomain {
    domain: string
    verified: boolean
    senders: IntegrationType[]
}

const LOCAL_PART_PATTERN = /^[a-z0-9](?:[a-z0-9._+-]*[a-z0-9])?$/i

const isVerifiedSender = (sender: IntegrationType): boolean => sender.config?.verified === true

