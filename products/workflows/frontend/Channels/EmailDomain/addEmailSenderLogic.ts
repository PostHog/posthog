export const addEmailSenderLogic = kea<addEmailSenderLogicType>([
    path(['products', 'workflows', 'frontend', 'Channels', 'EmailDomain', 'addEmailSenderLogic']),
    connect(() => ({
        values: [integrationsLogic, ['integrations', 'domainGroupedEmailIntegrations'], teamLogic, ['currentTeamId']],
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        openAddSender: (domain: string | null, entry: AddEmailSenderEntry) => ({ domain, entry }),
        closeAddSender: true,
        selectDomain: (domain: string) => ({ domain }),
        setLocalPart: (localPart: string) => ({ localPart }),
        setSenderNameInput: (name: string) => ({ name }),
        setSubmitError: (error: string | null) => ({ error }),
        useNewDomain: true,
        finishVerification: true,
    }),
    reducers({
        isOpen: [
            false,
            {
                openAddSender: () => true,
                closeAddSender: () => false,
            },
        ],
        entry: [
            'catalog' as AddEmailSenderEntry,
            {
                openAddSender: (_, { entry }) => entry,
            },
        ],
        requestedDomain: [
            null as string | null,
            {
                openAddSender: (_, { domain }) => domain,
                selectDomain: (_, { domain }) => domain,
            },
        ],
        localPart: [
            '',
            {
                openAddSender: () => '',
                setLocalPart: (_, { localPart }) => localPart.trim(),
            },
        ],
        senderNameInput: [
            null as string | null,
            {
                openAddSender: () => null,
                setSenderNameInput: (_, { name }) => name,
            },
        ],
        submitError: [
            null as string | null,
            {
                setSubmitError: (_, { error }) => error,
                openAddSender: () => null,
                selectDomain: () => null,
                setLocalPart: () => null,
            },
        ],
    }),
    selectors({
        domains: [
            (s) => [s.domainGroupedEmailIntegrations],
            (groups: EmailIntegrationDomainGroupedType[]): SenderDomain[] =>
                groups
                    .filter(({ domain }) => !!domain)
                    .map(({ domain, integrations }) => ({
                        domain,
                        senders: integrations,
                        verified: integrations.every(isVerifiedSender),
                    })),
        ],
        selectedDomain: [
            (s) => [s.requestedDomain, s.domains],
            (requestedDomain: string | null, domains: SenderDomain[]): SenderDomain | null =>
                domains.find((candidate) => candidate.domain === requestedDomain) ??
                domains.find((candidate) => candidate.verified) ??
                domains[0] ??
                null,
        ],
        senderName: [
            (s) => [s.senderNameInput, s.selectedDomain],
            (senderNameInput: string | null, selectedDomain: SenderDomain | null): string =>
                senderNameInput ?? selectedDomain?.senders[0]?.config?.name ?? '',
        ],
        fromAddress: [
            (s) => [s.localPart, s.selectedDomain],
            (localPart: string, selectedDomain: SenderDomain | null): string | null =>
                localPart && selectedDomain ? `${localPart}@${selectedDomain.domain}`.toLowerCase() : null,
        ],
        submitDisabledReason: [
            (s) => [s.selectedDomain, s.localPart, s.senderName, s.fromAddress, s.integrations],
            (
                selectedDomain: SenderDomain | null,
                localPart: string,
                senderName: string,
                fromAddress: string | null,
                integrations: IntegrationType[] | null
            ): string | null => {
                if (!selectedDomain) {
                    return 'Pick a domain'
                }
                if (!selectedDomain.verified) {
                    return 'Finish verifying this domain first'
                }
                if (!senderName.trim()) {
                    return 'Enter a sender name'
                }
                if (!localPart) {
                    return 'Enter the part of the address before the @'
                }
                if (!LOCAL_PART_PATTERN.test(localPart)) {
                    return 'Use letters, numbers, dots, dashes, plus signs or underscores'
                }
                if (integrations?.some((sender) => sender.kind === 'email' && sender.config?.email === fromAddress)) {
                    return `${fromAddress} is already a sender`
                }
                return null
            },
        ],
    }),
    loaders(({ values, actions }) => ({
        addedSender: [
            null as AddedSender | null,
            {
                addSender: async (): Promise<AddedSender | null> => {
                    const { selectedDomain, fromAddress, currentTeamId, submitDisabledReason } = values
                    const sibling = selectedDomain?.senders[0]
                    if (submitDisabledReason || !fromAddress || !currentTeamId || !selectedDomain || !sibling) {
                        return null
                    }
                    const submitted = {
                        email: fromAddress,
                        domain: selectedDomain.domain,
                        existingSendersOnDomain: selectedDomain.senders.length,
                    }
                    actions.setSubmitError(null)
                    let created: IntegrationConfigApi
                    try {
                        created = await integrationsCreate(String(currentTeamId), {
                            kind: 'email',
                            config: {
                                email: submitted.email,
                                name: values.senderName.trim(),
                                provider: sibling.config.provider,
                                mail_from_subdomain: sibling.config.mail_from_subdomain,
                            },
                        })
                    } catch (error) {
                        actions.setSubmitError(
                            (error instanceof ApiError && error.detail) ||
                                'Could not add the sender. Try again in a moment.'
                        )
                        return null
                    }
                    const verification = await integrationsEmailVerifyCreate(String(currentTeamId), created.id).catch(
                        () => null
                    )
                    return { ...submitted, sender: created, verified: verification?.status === 'success' }
                },
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        openAddSender: ({ entry }) => {
            // pinned: analytics event name
            posthog.capture('email sender add started', { entry, domain_count: values.domains.length })
        },
        addSenderSuccess: ({ addedSender }) => {
            if (!addedSender) {
                return
            }
            // pinned: analytics event name
            posthog.capture('email sender added', {
                entry: values.entry,
                verified: addedSender.verified,
                existing_senders_on_domain: addedSender.existingSendersOnDomain,
            })
            if (addedSender.verified) {
                lemonToast.success(`Added ${addedSender.email} as a sender`)
                actions.closeAddSender()
            } else {
                actions.selectDomain(addedSender.domain)
            }
            actions.loadIntegrations()
        },
        useNewDomain: () => {
            actions.closeAddSender()
            openEmailDomainSetupPage('add_sender')
        },
        finishVerification: () => {
            const senders = values.selectedDomain?.senders ?? []
            const sender = senders.find((candidate) => !isVerifiedSender(candidate)) ?? senders[0]
            actions.closeAddSender()
            if (sender) {
                router.actions.push(urls.workflowsEmailDomain(sender.id))
            }
        },
    })),
])
