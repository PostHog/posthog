export const POLL_FAST_MS = 10_000
export const POLL_FAST_WINDOW_MS = 5 * 60_000
export const POLL_SLOW_MS = 30_000
export const POLL_MAX_MS = 30 * 60_000

const STATUS_ERRORS_THAT_END_POLLING = [400, 403, 404]
// A DMARC or apex SPF record often exists before the person adds anything, so finding one proves nothing about setup.
const RECORD_KINDS_THAT_PREDATE_SETUP: EmailDomainSetupRecordKindEnumApi[] = ['dmarc', 'spf']

const isRecordFound = (record: EmailDomainStatusRecordApi): boolean => record.status !== 'pending'
const isSetupEvidence = (record: EmailDomainStatusRecordApi): boolean =>
    isRecordFound(record) && !RECORD_KINDS_THAT_PREDATE_SETUP.includes(record.kind)

