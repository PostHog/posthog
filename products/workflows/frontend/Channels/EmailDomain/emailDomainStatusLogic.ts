/** Reads the domain's setup status and keeps polling it while the page is open and the domain is not verified. */
export const emailDomainStatusLogic = kea<emailDomainStatusLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'Channels', 'EmailDomain', 'emailDomainStatusLogic', key]),
    props({} as EmailDomainLogicProps),
    key(({ id }) => id),
    connect((props: EmailDomainLogicProps) => ({
        values: [teamLogic, ['currentTeamId'], emailDomainSenderLogic(props), ['domain']],
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        loadStatus: (refresh: boolean = false) => ({ refresh }),
        statusCheckFailed: (httpStatus: number | null) => ({ httpStatus }),
        startPolling: true,
        schedulePoll: true,
        stopPolling: true,
        recheck: true,
        checkAgain: true,
    }),
    loaders(({ values, actions }) => ({
        status: [
            null as EmailDomainStatusApi | null,
            {
                loadStatus: async ({ refresh }): Promise<EmailDomainStatusApi | null> => {
                    const { integrationId, currentTeamId } = values
                    if (!integrationId || !currentTeamId) {
                        return null
                    }
                    try {
                        return await integrationsEmailStatusRetrieve(String(currentTeamId), integrationId, { refresh })
                    } catch (error) {
                        actions.statusCheckFailed(error instanceof ApiError ? (error.status ?? null) : null)
                        return values.status
                    }
                },
            },
        ],
        restartResult: [
            null as boolean | null,
            {
                restartVerification: async (): Promise<boolean | null> => {
                    if (!values.integrationId) {
                        return null
                    }
                    try {
                        // nosemgrep: prefer-codegen-api-namespaced-integrations -- the generated integrationsEmailVerifyCreate returns void and demands a config body the endpoint ignores
                        await api.integrations.verifyEmail(values.integrationId)
                        return true
                    } catch {
                        lemonToast.error('Could not restart verification. Try again in a moment.')
                        return false
                    }
                },
            },
        ],
    })),
    reducers({
        lastCheckFailed: [
            false,
            {
                loadStatus: () => false,
                statusCheckFailed: () => true,
            },
        ],
        statusUnavailable: [
            false,
            {
                statusCheckFailed: () => true,
                loadStatusSuccess: (state, { status }) => (status ? false : state),
            },
        ],
        pollingStartedAt: [
            null as number | null,
            {
                startPolling: () => Date.now(),
                recheck: () => Date.now(),
            },
        ],
        pollingStopped: [
            false,
            {
                stopPolling: () => true,
                recheck: () => false,
            },
        ],
    }),
    selectors({
        integrationId: [
            () => [(_, props: EmailDomainLogicProps) => props.id],
            (id: string): number | null => integrationIdOf(id),
        ],
        records: [
            (s) => [s.status],
            (status: EmailDomainStatusApi | null): EmailDomainStatusRecordApi[] => status?.records ?? [],
        ],
        foundCount: [
            (s) => [s.records],
            (records: EmailDomainStatusRecordApi[]): number => records.filter(isRecordFound).length,
        ],
        setupEvidenceFound: [
            (s) => [s.records],
            (records: EmailDomainStatusRecordApi[]): boolean => records.some(isSetupEvidence),
        ],
        missingRecords: [
            (s) => [s.records, s.pollingStopped, s.status],
            (
                records: EmailDomainStatusRecordApi[],
                pollingStopped: boolean,
                status: EmailDomainStatusApi | null
            ): EmailDomainStatusRecordApi[] =>
                pollingStopped || status?.status === 'temporary_failure'
                    ? records.filter((record) => !isRecordFound(record))
                    : [],
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadStatusSuccess: ({ status }) => {
            if (values.integrationId === null) {
                return
            }
            // A failed check keeps the last status, which must not end polling as if it were fresh.
            if (values.lastCheckFailed) {
                if (values.pollingStartedAt === null) {
                    actions.startPolling()
                }
                actions.schedulePoll()
                return
            }
            if (status?.verified || status?.status === 'failed') {
                cache.disposables.dispose('poll')
                if (status.verified) {
                    actions.loadIntegrations()
                }
                return
            }
            if (values.pollingStartedAt === null) {
                actions.startPolling()
            }
            actions.schedulePoll()
        },
        schedulePoll: () => {
            if (values.pollingStopped) {
                return
            }
            const elapsed = Date.now() - (values.pollingStartedAt ?? Date.now())
            if (elapsed >= POLL_MAX_MS) {
                actions.stopPolling()
                return
            }
            const delay = elapsed < POLL_FAST_WINDOW_MS ? POLL_FAST_MS : POLL_SLOW_MS
            cache.disposables.add(() => {
                const timer = window.setTimeout(() => actions.loadStatus(), delay)
                return () => clearTimeout(timer)
            }, 'poll')
        },
        stopPolling: () => {
            cache.disposables.dispose('poll')
        },
        statusCheckFailed: ({ httpStatus }) => {
            if (httpStatus && STATUS_ERRORS_THAT_END_POLLING.includes(httpStatus)) {
                actions.stopPolling()
            }
        },
        recheck: () => {
            actions.loadStatus(true)
        },
        checkAgain: () => {
            // pinned: analytics event name
            posthog.capture('email domain check again clicked', { domain: values.domain })
            actions.recheck()
        },
        restartVerificationSuccess: ({ restartResult }) => {
            if (restartResult) {
                actions.recheck()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.integrationId !== null) {
            actions.loadStatus()
        }
    }),
])
