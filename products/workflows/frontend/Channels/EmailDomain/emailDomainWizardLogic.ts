/** The domain step: picks or types the domain, shapes the sender address and creates the sender. */
export const emailDomainWizardLogic = kea<emailDomainWizardLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'Channels', 'EmailDomain', 'emailDomainWizardLogic', key]),
    props({} as EmailDomainWizardLogicProps),
    key(({ logicKey }) => logicKey),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeam', 'currentTeamId'],
            userLogic,
            ['user'],
            organizationLogic,
            ['currentOrganization'],
            integrationsLogic,
            ['integrations'],
            preflightLogic,
            ['preflight'],
        ],
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        selectDomain: (domain: string) => ({ domain }),
        clearDomain: true,
        setCustomDomainInput: (value: string) => ({ value }),
        useCustomDomain: true,
        setSendPrefix: (prefix: string) => ({ prefix }),
        setCustomPrefixOpen: (open: boolean) => ({ open }),
        setBouncePrefix: (prefix: string) => ({ prefix }),
        setAdvancedOpen: (open: boolean) => ({ open }),
        setLocalPart: (localPart: string) => ({ localPart }),
        setSenderNameInput: (name: string) => ({ name }),
        setReplyTo: (replyTo: string) => ({ replyTo }),
        setSubmitError: (error: string | null) => ({ error }),
        setLocalProvider: (provider: EmailSenderProvider) => ({ provider }),
    }),
    loaders(({ values, actions }) => ({
        eventHosts: [
            [] as EventHost[],
            {
                loadEventHosts: async (): Promise<EventHost[]> => {
                    try {
                        const response = await api.queryHogQL(EVENT_HOSTS_QUERY, {
                            scene: Scene.WorkflowsEmailDomain,
                            productKey: ProductKey.WORKFLOWS,
                            name: 'email_domain_event_hosts',
                        })
                        return (response.results ?? []).map(([host, count]) => ({
                            host: String(host),
                            count: Number(count),
                        }))
                    } catch {
                        return []
                    }
                },
            },
        ],
        createdSender: [
            null as IntegrationConfigApi | null,
            {
                createSender: async (): Promise<IntegrationConfigApi | null> => {
                    const { selectedDomain, sendingDomain, currentTeamId, localPart, bouncePrefix, domainSender } =
                        values
                    if (!selectedDomain || !sendingDomain || !currentTeamId) {
                        return null
                    }
                    actions.setSubmitError(null)
                    try {
                        return await integrationsCreate(String(currentTeamId), {
                            kind: 'email',
                            config: {
                                email: `${localPart || DEFAULT_LOCAL_PART}@${sendingDomain}`,
                                name: values.senderName.trim() || values.suggestedSenderName,
                                ...(values.replyTo.trim() ? { reply_to: values.replyTo.trim() } : {}),
                                provider: values.senderProvider,
                                // The provider keeps one bounce subdomain per domain, so a new address reuses the existing one.
                                mail_from_subdomain:
                                    domainSender?.config?.mail_from_subdomain || bouncePrefix || DEFAULT_BOUNCE_PREFIX,
                            },
                        })
                    } catch (error) {
                        const detail = error instanceof ApiError ? error.detail : null
                        actions.setSubmitError(detail || 'Could not create the sender. Try again in a moment.')
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        selectedDomain: [
            null as string | null,
            {
                selectDomain: (_, { domain }) => domain,
                clearDomain: () => null,
            },
        ],
        customDomainInput: [
            '',
            {
                setCustomDomainInput: (_, { value }) => value,
                selectDomain: () => '',
            },
        ],
        // null until the person types a name, so the suggestion keeps following the picked domain.
        senderNameInput: [
            null as string | null,
            {
                setSenderNameInput: (_, { name }) => name,
            },
        ],
        replyTo: [
            '',
            {
                setReplyTo: (_, { replyTo }) => replyTo,
            },
        ],
        localPart: [
            DEFAULT_LOCAL_PART,
            {
                setLocalPart: (_, { localPart }) => localPart,
            },
        ],
        sendPrefix: [
            DEFAULT_SEND_PREFIX,
            {
                setSendPrefix: (_, { prefix }) => asSubdomainLabel(prefix),
            },
        ],
        customPrefixOpen: [
            false,
            {
                setCustomPrefixOpen: (_, { open }) => open,
            },
        ],
        bouncePrefix: [
            DEFAULT_BOUNCE_PREFIX,
            {
                setBouncePrefix: (_, { prefix }) => asSubdomainLabel(prefix),
            },
        ],
        advancedOpen: [
            false,
            {
                setAdvancedOpen: (_, { open }) => open,
            },
        ],
        submitError: [
            null as string | null,
            {
                setSubmitError: (_, { error }) => error,
                selectDomain: () => null,
                clearDomain: () => null,
            },
        ],
        localProvider: [
            'maildev' as EmailSenderProvider,
            {
                setLocalProvider: (_, { provider }) => provider,
            },
        ],
    }),
    selectors({
        isLocalStack: [(s) => [s.preflight], (preflight: PreflightStatus | null): boolean => !!preflight?.is_debug],
        // A local stack has no SES by default, so it starts on Maildev. Elsewhere Maildev does not exist.
        senderProvider: [
            (s) => [s.isLocalStack, s.localProvider],
            (isLocalStack: boolean, localProvider: EmailSenderProvider): EmailSenderProvider =>
                isLocalStack ? localProvider : 'ses',
        ],
        inferredDomains: [
            (s) => [s.currentTeam, s.user, s.eventHosts],
            (
                currentTeam: TeamPublicType | TeamType | null,
                user: UserType | null,
                eventHosts: EventHost[]
            ): InferredDomain[] => inferDomains(currentTeam?.app_urls ?? [], user?.email ?? null, eventHosts),
        ],
        customDomain: [
            (s) => [s.customDomainInput],
            (customDomainInput: string): CustomDomain => {
                const { domain, localPart } = normalizeDomainInput(customDomainInput)
                return { domain, localPart, problem: domainProblemOf(domain) }
            },
        ],
        selectedIsInferred: [
            (s) => [s.selectedDomain, s.inferredDomains],
            (selectedDomain: string | null, inferredDomains: InferredDomain[]): boolean =>
                inferredDomains.some((candidate) => candidate.domain === selectedDomain),
        ],
        sendingDomain: [
            (s) => [s.selectedDomain, s.sendPrefix],
            (selectedDomain: string | null, sendPrefix: string): string | null =>
                selectedDomain ? (sendPrefix ? `${sendPrefix}.${selectedDomain}` : selectedDomain) : null,
        ],
        suggestedSenderName: [
            (s) => [s.currentOrganization, s.selectedDomain],
            (currentOrganization: OrganizationType | null, selectedDomain: string | null): string =>
                selectedDomain ? defaultSenderName(currentOrganization?.name, selectedDomain) : '',
        ],
        senderName: [
            (s) => [s.senderNameInput, s.suggestedSenderName],
            (senderNameInput: string | null, suggestedSenderName: string): string =>
                senderNameInput ?? suggestedSenderName,
        ],
        fromAddress: [
            (s) => [s.sendingDomain, s.localPart],
            (sendingDomain: string | null, localPart: string): string | null =>
                sendingDomain ? `${localPart || DEFAULT_LOCAL_PART}@${sendingDomain}` : null,
        ],
        domainSender: [
            (s) => [s.integrations, s.sendingDomain],
            (integrations: IntegrationType[] | null, sendingDomain: string | null): IntegrationType | null =>
                integrations?.find((integration) => isEmailSenderOn(integration, sendingDomain)) ?? null,
        ],
        existingSender: [
            (s) => [s.integrations, s.fromAddress],
            (integrations: IntegrationType[] | null, fromAddress: string | null): IntegrationType | null =>
                integrations?.find(
                    (integration) => integration.kind === 'email' && integration.config?.email === fromAddress
                ) ?? null,
        ],
    }),
    listeners(({ actions, values, props }) => ({
        useCustomDomain: () => {
            const { domain, localPart, problem } = values.customDomain
            if (!domain || problem) {
                return
            }
            if (localPart) {
                actions.setLocalPart(localPart)
            }
            actions.selectDomain(domain)
            // A full address on a domain that already sends is meant exactly as typed, without the recommended subdomain.
            if (localPart && values.integrations?.some((integration) => isEmailSenderOn(integration, domain))) {
                actions.setSendPrefix('')
            }
        },
        createSenderSuccess: async ({ createdSender }) => {
            if (!createdSender) {
                return
            }
            actions.loadIntegrations()
            props.onCreated(createdSender)
            const detection = await integrationsDomainConnectCheckRetrieve(String(values.currentTeamId), {
                domain: values.sendingDomain ?? '',
                include_email_setup: true,
            }).catch(() => null)
            // pinned: analytics event name
            posthog.capture('email domain submitted', {
                detected_provider: detection?.dns_host?.name ?? detection?.provider_name ?? null,
                has_domain_connect: detection?.supported ?? false,
                existing_senders: detection?.existing_email_tools ?? [],
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadEventHosts()
    }),
])
