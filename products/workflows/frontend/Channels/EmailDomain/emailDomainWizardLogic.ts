const EVENT_HOSTS_QUERY = hogql`SELECT properties.$host AS host, count() AS events
    FROM events
    WHERE timestamp >= now() - INTERVAL 30 DAY
    AND properties.$host IS NOT NULL
    AND properties.$host != ''
    GROUP BY host
    ORDER BY events DESC
    LIMIT 5`

export type EmailSenderProvider = 'ses' | 'maildev'

const isEmailSenderOn = (integration: IntegrationType, domain: string | null): boolean =>
    integration.kind === 'email' && integration.config?.domain === domain

