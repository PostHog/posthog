/** Finds who hosts the domain's DNS and, when that host supports Domain Connect, sends the person there to add the records in one click. */
export const emailDomainAutoConfigureLogic = kea<emailDomainAutoConfigureLogicType>([
    path((key) => [
        'products',
        'workflows',
        'frontend',
        'Channels',
        'EmailDomain',
        'emailDomainAutoConfigureLogic',
        key,
    ]),
    props({} as EmailDomainLogicProps),
    key(({ id }) => id),
    connect((props: EmailDomainLogicProps) => ({
        values: [teamLogic, ['currentTeamId'], emailDomainSenderLogic(props), ['domain', 'integrationId']],
        actions: [emailDomainSenderLogic(props), ['loadSenderSuccess'], emailDomainStatusLogic(props), ['recheck']],
    })),
    actions({
        openAutoConfigure: true,
        setAutoConfigureLoading: (loading: boolean) => ({ loading }),
        returnFromAutoConfigure: true,
    }),
    loaders(({ values }) => ({
        detection: [
            null as EmailDomainConnectCheckApi | null,
            {
                loadDetection: async (): Promise<EmailDomainConnectCheckApi | null> => {
                    if (!values.domain) {
                        return null
                    }
                    try {
                        // nosemgrep: prefer-codegen-api-namespaced-integrations -- the generated integrationsDomainConnectCheckRetrieve has no domain query parameter
                        return await api.integrations.domainConnectCheck(values.domain)
                    } catch {
                        return UNKNOWN_HOST
                    }
                },
            },
        ],
    })),
    reducers({
        autoConfigureLoading: [
            false,
            {
                setAutoConfigureLoading: (_, { loading }) => loading,
            },
        ],
        returnedFromAutoConfigure: [
            false,
            {
                returnFromAutoConfigure: () => true,
            },
        ],
    }),
    selectors({
        dnsHost: [
            (s) => [s.detection],
            (detection: EmailDomainConnectCheckApi | null): EmailDomainDnsHostApi | null => detection?.dns_host ?? null,
        ],
        supportsDomainConnect: [
            (s) => [s.detection],
            (detection: EmailDomainConnectCheckApi | null): boolean =>
                detection?.supported === true && !!detection.provider_name,
        ],
        hostName: [
            (s) => [s.detection, s.dnsHost],
            (detection: EmailDomainConnectCheckApi | null, dnsHost: EmailDomainDnsHostApi | null): string | null =>
                dnsHost?.name ?? detection?.provider_name ?? null,
        ],
        pageUrl: [
            (s) => [s.currentTeamId, s.integrationId],
            (currentTeamId: number | null, integrationId: number | null): string | null =>
                currentTeamId && integrationId ? emailDomainPageUrl(currentTeamId, integrationId) : null,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadSenderSuccess: ({ sender }) => {
            if (sender && !values.detection) {
                actions.loadDetection()
            }
        },
        loadDetectionSuccess: () => {
            if (values.returnedFromAutoConfigure && !cache.returnReported) {
                cache.returnReported = true
                // pinned: analytics event name
                posthog.capture('email domain auto configure returned', { provider: values.hostName })
            }
        },
        returnFromAutoConfigure: () => {
            actions.recheck()
        },
        openAutoConfigure: async () => {
            const { integrationId, pageUrl } = values
            if (!integrationId || !pageUrl) {
                return
            }
            // pinned: analytics event name
            posthog.capture('email domain auto configure clicked', { provider: values.hostName })
            // Opened before the request so the click's user activation still covers it; a later open is a popup.
            const tab = openBlankTab()
            actions.setAutoConfigureLoading(true)
            try {
                // nosemgrep: prefer-codegen-api-namespaced-integrations -- the generated integrationsDomainConnectApplyUrlCreate returns void, and this reads the apply URL
                const { url } = await api.integrations.domainConnectApplyUrl({
                    context: 'email',
                    integration_id: integrationId,
                    redirect_uri: `${pageUrl}?${DOMAIN_CONNECT_RETURN_PARAM}=email`,
                })
                showInTab(tab, url)
            } catch (error) {
                tab?.close()
                const detail = error instanceof ApiError ? error.detail : null
                lemonToast.error(
                    detail || `Could not open ${values.hostName ?? 'your DNS host'}. Add the settings yourself instead.`
                )
            } finally {
                actions.setAutoConfigureLoading(false)
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.integrationId !== null && returnedFromDomainConnect()) {
            actions.returnFromAutoConfigure()
        }
    }),
])
