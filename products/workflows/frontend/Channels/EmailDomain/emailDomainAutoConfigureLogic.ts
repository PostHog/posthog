// pinned: URL search param, the Domain Connect redirect_uri carries it back to this page
export const DOMAIN_CONNECT_RETURN_PARAM = 'domain_connect'

const UNKNOWN_HOST: EmailDomainConnectCheckApi = {
    supported: false,
    provider_name: null,
    available_providers: [],
    dns_host: null,
    existing_email_tools: [],
}

const openBlankTab = (): Window | null => window.open('', '_blank')

const showInTab = (tab: Window | null, url: string): void => {
    if (!tab) {
        window.location.assign(url)
        return
    }
    tab.opener = null
    tab.location.href = url
}

const returnedFromDomainConnect = (): boolean => {
    const { location, searchParams } = router.values
    if (searchParams[DOMAIN_CONNECT_RETURN_PARAM] !== 'email') {
        return false
    }
    const { [DOMAIN_CONNECT_RETURN_PARAM]: _, ...otherParams } = searchParams
    router.actions.replace(location.pathname, otherParams, location.hash)
    return true
}

