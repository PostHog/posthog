export type EmailDomainPhase = 'domain' | 'loading' | 'unavailable' | 'settings' | 'verifying' | 'ready'

export interface VerificationStep {
    key: 'domain_added' | 'records_found' | 'verified'
    label: string
    detail: string
    state: 'done' | 'active' | 'todo' | 'stuck'
}

interface PhaseInput {
    integrationId: number | null
    sender: IntegrationConfigApi | null
    senderFailed: boolean
    status: EmailDomainStatusApi | null
    statusUnavailable: boolean
    recordsAdded: boolean
    returnedFromAutoConfigure: boolean
    setupEvidenceFound: boolean
}

const STATUSES_IN_PROGRESS: EmailDomainStatusApi['status'][] = ['records_found', 'temporary_failure', 'failed']

const phaseOf = ({
    integrationId,
    sender,
    senderFailed,
    status,
    statusUnavailable,
    recordsAdded,
    returnedFromAutoConfigure,
    setupEvidenceFound,
}: PhaseInput): EmailDomainPhase => {
    if (integrationId === null) {
        return 'domain'
    }
    if (senderFailed || (!status && statusUnavailable)) {
        return 'unavailable'
    }
    if (!sender || !status) {
        return 'loading'
    }
    if (status.verified) {
        return 'ready'
    }
    const inProgress = recordsAdded || returnedFromAutoConfigure || STATUSES_IN_PROGRESS.includes(status.status)
    return inProgress || setupEvidenceFound ? 'verifying' : 'settings'
}

interface StepsInput {
    status: EmailDomainStatusApi | null
    phase: EmailDomainPhase
    domain: string | null
    records: EmailDomainStatusRecordApi[]
    foundCount: number
    pollingStopped: boolean
}

const verificationStepsOf = ({
    status,
    phase,
    domain,
    records,
    foundCount,
    pollingStopped,
}: StepsInput): VerificationStep[] => {
    const verified = phase === 'ready'
    const verifying = phase === 'verifying'
    const allFound = records.length > 0 && foundCount === records.length
    const sesFailed = status?.status === 'failed'
    const stuck = pollingStopped || status?.status === 'temporary_failure'
    const foundState: VerificationStep['state'] = verified
        ? 'done'
        : stuck
          ? 'stuck'
          : allFound
            ? 'done'
            : verifying
              ? 'active'
              : 'todo'
    const verifiedState: VerificationStep['state'] = verified
        ? 'done'
        : sesFailed
          ? 'stuck'
          : allFound
            ? 'active'
            : 'todo'
    const foundDetail =
        verifying || verified
            ? `${foundCount} of ${records.length} found`
            : records.length
              ? `${records.length} settings to add`
              : 'Nothing to add yet'
    const verifiedDetail = verified
        ? 'Inboxes trust your emails'
        : sesFailed
          ? 'Verification stopped. Restart it below.'
          : allFound
            ? 'Records look right, waiting for confirmation'
            : 'Takes about a minute after the settings are found'
    return [
        { key: 'domain_added', label: 'Domain added', detail: domain ?? '', state: 'done' },
        { key: 'records_found', label: 'Settings found at your DNS host', detail: foundDetail, state: foundState },
        { key: 'verified', label: 'Ready to send', detail: verifiedDetail, state: verifiedState },
    ]
}

