/** The sending domain page: composes the step to show from the sender, its status and the setup path the person took. */
export const emailDomainLogic = kea<emailDomainLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'Channels', 'EmailDomain', 'emailDomainLogic', key]),
    props({} as EmailDomainLogicProps),
    key(({ id }) => id),
    connect((props: EmailDomainLogicProps) => ({
        values: [
            emailDomainSenderLogic(props),
            ['domain', 'integrationId', 'sender', 'senderFailed', 'senderLoading'],
            emailDomainStatusLogic(props),
            [
                'foundCount',
                'pollingStopped',
                'records',
                'setupEvidenceFound',
                'status',
                'statusUnavailable',
                'statusLoading',
            ],
            emailDomainManualSetupLogic(props),
            ['recordsAdded'],
            emailDomainAutoConfigureLogic(props),
            ['returnedFromAutoConfigure'],
        ],
        actions: [emailDomainSenderLogic(props), ['loadSender'], emailDomainStatusLogic(props), ['recheck']],
    })),
    actions({
        retry: true,
    }),
    selectors({
        phase: [
            (s) => [
                s.integrationId,
                s.sender,
                s.senderFailed,
                s.status,
                s.statusUnavailable,
                s.recordsAdded,
                s.returnedFromAutoConfigure,
                s.setupEvidenceFound,
            ],
            (
                integrationId: number | null,
                sender: IntegrationConfigApi | null,
                senderFailed: boolean,
                status: EmailDomainStatusApi | null,
                statusUnavailable: boolean,
                recordsAdded: boolean,
                returnedFromAutoConfigure: boolean,
                setupEvidenceFound: boolean
            ): EmailDomainPhase =>
                phaseOf({
                    integrationId,
                    sender,
                    senderFailed,
                    status,
                    statusUnavailable,
                    recordsAdded,
                    returnedFromAutoConfigure,
                    setupEvidenceFound,
                }),
        ],
        verificationSteps: [
            (s) => [s.status, s.phase, s.domain, s.records, s.foundCount, s.pollingStopped],
            (
                status: EmailDomainStatusApi | null,
                phase: EmailDomainPhase,
                domain: string | null,
                records: EmailDomainStatusRecordApi[],
                foundCount: number,
                pollingStopped: boolean
            ): VerificationStep[] =>
                verificationStepsOf({ status, phase, domain, records, foundCount, pollingStopped }),
        ],
        breadcrumbs: [
            (s) => [s.domain, s.integrationId],
            (domain: string | null, integrationId: number | null): Breadcrumb[] => [
                { key: Scene.Workflows, name: 'Workflows', path: urls.workflows(), iconType: 'workflows' },
                { key: 'channels', name: 'Channels', path: urls.workflows('channels'), iconType: 'workflows' },
                {
                    key: [Scene.WorkflowsEmailDomain, integrationId ?? 'new'],
                    name: domain ?? 'New sending domain',
                    iconType: 'workflows',
                },
            ],
        ],
    }),
    listeners(({ actions, values }) => ({
        retry: () => {
            if (values.senderFailed) {
                actions.loadSender()
            }
            if (values.statusUnavailable) {
                actions.recheck()
            }
        },
    })),
])
