/** Hands the DNS setup to a coding agent: builds the prompt for the sender and offers it to copy or open in Claude. */
export const emailDomainAgentLogic = kea<emailDomainAgentLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'Channels', 'EmailDomain', 'emailDomainAgentLogic', key]),
    props({} as EmailDomainLogicProps),
    key(({ id }) => id),
    connect((props: EmailDomainLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            emailDomainSenderLogic(props),
            ['currentTeamId', 'domain', 'integrationId', 'mailFromSubdomain'],
            emailDomainStatusLogic(props),
            ['records'],
            emailDomainAutoConfigureLogic(props),
            ['dnsHost', 'pageUrl', 'supportsDomainConnect'],
        ],
    })),
    actions({
        openAgentModal: true,
        closeAgentModal: true,
        setAgentUsesBrowser: (agentUsesBrowser: boolean) => ({ agentUsesBrowser }),
        copyPrompt: true,
        promptOpenedInClaude: true,
    }),
    reducers({
        agentModalOpen: [
            false,
            {
                openAgentModal: () => true,
                closeAgentModal: () => false,
            },
        ],
        agentUsesBrowser: [
            false,
            {
                setAgentUsesBrowser: (_, { agentUsesBrowser }) => agentUsesBrowser,
            },
        ],
    }),
    selectors({
        agentSetupEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean =>
                !!featureFlags[FEATURE_FLAGS.WORKFLOWS_EMAIL_DOMAIN_AGENT_SETUP],
        ],
        setupPrompt: [
            (s) => [
                s.domain,
                s.mailFromSubdomain,
                s.currentTeamId,
                s.integrationId,
                s.pageUrl,
                s.dnsHost,
                s.supportsDomainConnect,
                s.records,
                s.agentUsesBrowser,
            ],
            (
                domain: string | null,
                mailFromSubdomain: string,
                currentTeamId: number | null,
                integrationId: number | null,
                pageUrl: string | null,
                dnsHost: EmailDomainDnsHostApi | null,
                supportsDomainConnect: boolean,
                records: EmailDomainStatusRecordApi[],
                agentUsesBrowser: boolean
            ): string =>
                domain && integrationId && currentTeamId && pageUrl
                    ? buildSetupPrompt({
                          domain,
                          mailFromSubdomain,
                          projectId: currentTeamId,
                          integrationId,
                          pageUrl,
                          dnsHost,
                          supportsDomainConnect,
                          records,
                          agentUsesBrowser,
                      })
                    : '',
        ],
        claudeUrl: [
            (s) => [s.setupPrompt],
            (setupPrompt: string): string => `https://claude.ai/new?q=${encodeURIComponent(setupPrompt)}`,
        ],
    }),
    listeners(({ values }) => ({
        copyPrompt: async () => {
            if (await copyToClipboard(values.setupPrompt, 'prompt', { silent: true })) {
                // pinned: analytics event name
                posthog.capture('email domain setup prompt copied', { browser: values.agentUsesBrowser })
                lemonToast.success('Prompt copied. Paste it into your agent.')
            }
        },
        promptOpenedInClaude: () => {
            // pinned: analytics event name
            posthog.capture('email domain setup prompt opened in claude', { browser: values.agentUsesBrowser })
        },
    })),
])
