/** The email sender behind the page: loads it, edits its name, records how its DNS was set up, and sends a test email. */
export const emailDomainSenderLogic = kea<emailDomainSenderLogicType>([
    path((key) => ['products', 'workflows', 'frontend', 'Channels', 'EmailDomain', 'emailDomainSenderLogic', key]),
    props({} as EmailDomainLogicProps),
    key(({ id }) => id),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], userLogic, ['user']],
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        setSenderName: (name: string) => ({ name }),
        saveSender: true,
        senderSaved: (sender: IntegrationConfigApi) => ({ sender }),
        saveSenderFailed: true,
        recordSetupMethod: (method: EmailSetupMethod) => ({ method }),
    }),
    loaders(({ values }) => ({
        sender: [
            null as IntegrationConfigApi | null,
            {
                loadSender: async (): Promise<IntegrationConfigApi | null> => {
                    const { integrationId, currentTeamId } = values
                    if (!integrationId || !currentTeamId) {
                        return null
                    }
                    return await integrationsRetrieve(String(currentTeamId), integrationId)
                },
                recordSetupMethod: async ({ method }): Promise<IntegrationConfigApi | null> => {
                    const { integrationId, currentTeamId, senderConfig, sender } = values
                    if (!integrationId || !currentTeamId || !senderConfig) {
                        return sender
                    }
                    try {
                        return await integrationsEmailPartialUpdate(String(currentTeamId), integrationId, {
                            kind: 'email',
                            config: { ...senderConfig, setup_method: method },
                        })
                    } catch {
                        return sender
                    }
                },
            },
        ],
        testSendResult: [
            null as HogflowTestResult | null,
            {
                sendTestEmail: async (): Promise<HogflowTestResult | null> => {
                    const { integrationId, currentTeamId, user, domain } = values
                    const recipient = user?.email
                    if (!integrationId || !domain || !recipient) {
                        return null
                    }
                    try {
                        // nosemgrep: prefer-codegen-api-namespaced-workflows -- the generated hogFlowsInvocationsCreate returns void, and this reads the test result
                        return await api.hogFlows.createTestInvocation(
                            'new',
                            buildTestEmailInvocation({ integrationId, teamId: currentTeamId, domain, recipient })
                        )
                    } catch {
                        lemonToast.error('Could not send the test email. Try again in a moment.')
                        return null
                    }
                },
            },
        ],
    })),
    reducers({
        sender: {
            senderSaved: (_, { sender }) => sender,
        },
        senderSaving: [
            false,
            {
                saveSender: () => true,
                senderSaved: () => false,
                saveSenderFailed: () => false,
            },
        ],
        senderFailed: [
            false,
            {
                loadSender: () => false,
                loadSenderFailure: () => true,
            },
        ],
        senderName: [
            '',
            {
                setSenderName: (_, { name }) => name,
                loadSenderSuccess: (state, { sender }) => configOf(sender)?.name ?? state,
                senderSaved: (state, { sender }) => configOf(sender)?.name ?? state,
            },
        ],
        testEmailSent: [
            false,
            {
                sendTestEmailSuccess: (state, { testSendResult }) => testSendResult?.status === 'success' || state,
            },
        ],
    }),
    selectors({
        integrationId: [
            () => [(_, props: EmailDomainLogicProps) => props.id],
            (id: string): number | null => integrationIdOf(id),
        ],
        senderConfig: [
            (s) => [s.sender],
            (sender: IntegrationConfigApi | null): EmailSenderConfig | null => configOf(sender),
        ],
        domain: [
            (s) => [s.senderConfig],
            (senderConfig: EmailSenderConfig | null): string | null => senderConfig?.domain ?? null,
        ],
        fromAddress: [
            (s) => [s.senderConfig],
            (senderConfig: EmailSenderConfig | null): string | null => senderConfig?.email ?? null,
        ],
        mailFromSubdomain: [
            (s) => [s.senderConfig],
            (senderConfig: EmailSenderConfig | null): string =>
                senderConfig?.mail_from_subdomain || DEFAULT_MAIL_FROM_SUBDOMAIN,
        ],
        senderNameChanged: [
            (s) => [s.senderName, s.senderConfig],
            (senderName: string, senderConfig: EmailSenderConfig | null): boolean =>
                senderName !== (senderConfig?.name ?? ''),
        ],
    }),
    listeners(({ actions, values }) => ({
        saveSender: async () => {
            const { integrationId, currentTeamId, senderConfig } = values
            if (!integrationId || !currentTeamId || !senderConfig) {
                actions.saveSenderFailed()
                return
            }
            try {
                const saved = await integrationsEmailPartialUpdate(String(currentTeamId), integrationId, {
                    kind: 'email',
                    config: { ...senderConfig, name: values.senderName },
                })
                actions.senderSaved(saved)
            } catch {
                actions.saveSenderFailed()
                lemonToast.error('Could not save the sender name. Try again in a moment.')
            }
        },
        senderSaved: () => {
            actions.loadIntegrations()
            lemonToast.success('Sender name saved')
        },
        sendTestEmailSuccess: ({ testSendResult }) => {
            if (testSendResult?.status === 'success') {
                lemonToast.success(`Test email sent to ${values.user?.email}. Check your inbox.`)
            } else if (testSendResult) {
                lemonToast.error('Could not send the test email. Try again in a moment.')
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.integrationId !== null) {
            actions.loadSender()
        }
    }),
])
