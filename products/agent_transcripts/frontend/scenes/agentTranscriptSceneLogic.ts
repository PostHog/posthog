export const agentTranscriptSceneLogic = kea<agentTranscriptSceneLogicType>([
    path(['products', 'agent_transcripts', 'frontend', 'agentTranscriptSceneLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            agentTranscriptSubmissionLogic,
            ['currentOrganization', 'submission', 'submissionLoading', 'submissionLoadFailed'],
        ],
        actions: [agentTranscriptSubmissionLogic, ['loadSubmission', 'loadSubmissionSuccess', 'setSubmission']],
    })),
    actions({
        selectAgent: (agent: TranscriptAgentEnumApi) => ({ agent }),
        uploadTranscript: (file: File) => ({ file }),
        setUploadStep: (step: TranscriptUploadStep) => ({ step }),
        setUploadProgress: (fraction: number) => ({ fraction }),
        uploadTranscriptSuccess: true,
        uploadTranscriptFailure: (error: TranscriptUploadError) => ({ error }),
        reportPromptCopied: true,
    }),
    reducers({
        selectedAgent: [
            null as TranscriptAgentEnumApi | null,
            {
                selectAgent: (_, { agent }) => agent,
            },
        ],
        uploadStep: [
            null as TranscriptUploadStep | null,
            {
                setUploadStep: (_, { step }) => step,
                uploadTranscriptSuccess: () => null,
                uploadTranscriptFailure: () => null,
            },
        ],
        uploadProgress: [
            0,
            {
                uploadTranscript: () => 0,
                setUploadProgress: (_, { fraction }) => fraction,
            },
        ],
        uploadFileName: [
            null as string | null,
            {
                uploadTranscript: (_, { file }) => file.name,
            },
        ],
        uploadError: [
            null as TranscriptUploadError | null,
            {
                uploadTranscript: () => null,
                uploadTranscriptFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        variant: [
            (s) => [s.featureFlags],
            (featureFlags: agentTranscriptSceneLogicValues['featureFlags']) =>
                agentTranscriptRequestVariant(featureFlags),
        ],
        isUploading: [
            (s) => [s.uploadStep],
            (uploadStep: agentTranscriptSceneLogicValues['uploadStep']): boolean => uploadStep !== null,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadSubmissionSuccess: ({ submission }) => {
            // After a request for changes, the new upload most likely comes from the same agent.
            if (!values.selectedAgent && submission?.agent) {
                actions.selectAgent(submission.agent)
            }
        },
        uploadTranscript: async ({ file }, breakpoint) => {
            const organizationId = values.currentOrganization?.id
            const { submission, selectedAgent } = values
            if (!organizationId || !submission || !selectedAgent) {
                return
            }

            const fileError = checkTranscriptFile(file, submission)
            if (fileError) {
                actions.uploadTranscriptFailure(fileError)
                return
            }

            try {
                actions.setUploadStep('starting')
                const presignedUpload = await api.agentTranscriptsStartUploadCreate(organizationId, {
                    filename: file.name,
                    size_bytes: file.size,
                    agent: selectedAgent,
                })
                breakpoint()

                actions.setUploadStep('sending')
                const controller = new AbortController()
                // A hidden tab must keep uploading, so only leaving the page cancels the upload.
                cache.disposables.add(() => () => controller.abort(), STORAGE_UPLOAD_DISPOSABLE_KEY, {
                    pauseOnPageHidden: false,
                })
                await postFileToStorage({
                    presignedUpload,
                    file,
                    onProgress: actions.setUploadProgress,
                    signal: controller.signal,
                })
                breakpoint()

                actions.setUploadStep('checking')
                const state = await api.agentTranscriptsCompleteUploadCreate(organizationId)
                breakpoint()

                actions.setSubmission(state)
                actions.uploadTranscriptSuccess()
            } catch (error) {
                if (error instanceof Error && isBreakpoint(error)) {
                    throw error
                }
                // Leaving the page aborts the upload, and that failure is not one to show or count.
                breakpoint()

                const completionMayHaveSucceeded = values.uploadStep === 'checking' && !isServerRefusal(error)
                actions.uploadTranscriptFailure(transcriptUploadErrorFrom(error))

                // The server can commit the upload and the response still not arrive. A retry then finds
                // the transcript already in review and fails, so reload the submission to show its status.
                if (completionMayHaveSucceeded) {
                    actions.loadSubmission()
                }
            }
        },
        uploadTranscriptFailure: ({ error }) => {
            posthog.capture(UPLOAD_FAILED_EVENT, { code: error.code, variant: values.variant })
        },
        reportPromptCopied: () => {
            posthog.capture(PROMPT_COPIED_EVENT, { agent: values.selectedAgent, variant: values.variant })
        },
    })),
    afterMount(({ actions, values }) => {
        actions.loadSubmission()

        posthog.capture(PAGE_VIEWED_EVENT, { variant: values.variant })
    }),
])
