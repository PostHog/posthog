/** Where an upload is: asking for an upload form, sending the file to storage, or waiting for the server's checks. */
export type TranscriptUploadStep = 'starting' | 'sending' | 'checking'

// pinned: analytics event names, renaming them breaks the experiment's insights
export const PAGE_VIEWED_EVENT = 'agent transcript page viewed'
export const UPLOAD_FAILED_EVENT = 'agent transcript upload failed'
export const PROMPT_COPIED_EVENT = 'agent transcript prompt copied'

const STORAGE_UPLOAD_DISPOSABLE_KEY = 'storageUpload'

