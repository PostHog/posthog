import { MakeLogicType, actions, afterMount, kea, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { parseTranscript } from './parseTranscript'
import { TranscriptEntry, TranscriptEntryKind } from './transcriptEntries'

export const TRANSCRIPT_FILTERS = ['focus', 'all', 'message', 'user', 'thinking', 'tool', 'web', 'system'] as const
export type TranscriptFilter = (typeof TRANSCRIPT_FILTERS)[number]

/** What `?source=transcript` returns. The page is a staff page outside the app API, so it has no generated type. */
export interface StoredTranscript {
    agent: string
    filename: string
    text: string
}

export interface TranscriptViewerLogicProps {
    organizationId: string
}

export const ENTRIES_PER_PAGE = 150

async function readTranscript(organizationId: string): Promise<StoredTranscript> {
    const url = new URL(window.location.href)
    url.search = new URLSearchParams({ organization: organizationId, source: 'transcript' }).toString()
    const response = await fetch(url, { credentials: 'same-origin' })
    const body = response.headers.get('content-type')?.includes('application/json') ? await response.json() : null
    if (!response.ok || !body) {
        throw new Error(body?.detail ?? "Couldn't load the transcript. Refresh the page to check your admin session.")
    }
    return body
}

export function matchesFilter(kind: TranscriptEntryKind, filter: TranscriptFilter): boolean {
    return filter === 'all' || (filter === 'focus' ? kind !== 'system' : kind === filter)
}

function matchesSearch(entry: TranscriptEntry, query: string): boolean {
    return [entry.title, entry.text, entry.output ?? ''].some((field) => field.toLowerCase().includes(query))
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface transcriptViewerLogicValues {
    transcript: StoredTranscript | null
    transcriptLoading: boolean
    transcriptError: string | null
    filter: TranscriptFilter
    search: string
    showAll: boolean
    entries: TranscriptEntry[]
    counts: Record<TranscriptFilter, number>
    visibleEntries: TranscriptEntry[]
    shownEntries: TranscriptEntry[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface transcriptViewerLogicActions {
    loadTranscript: () => any
    loadTranscriptSuccess: (
        transcript: StoredTranscript,
        payload?: any
    ) => { transcript: StoredTranscript; payload?: any }
    loadTranscriptFailure: (error: string, errorObject?: any) => { error: string; errorObject?: any }
    setFilter: (filter: TranscriptFilter) => { filter: TranscriptFilter }
    setSearch: (search: string) => { search: string }
    showAllEntries: () => { value: true }
}

export type transcriptViewerLogicType = MakeLogicType<
    transcriptViewerLogicValues,
    transcriptViewerLogicActions,
    TranscriptViewerLogicProps
>

/** Loads one organization's transcript and decides which of its entries the viewer shows. */
export const transcriptViewerLogic = kea<transcriptViewerLogicType>([
    path(['products', 'agent_transcripts', 'frontend', 'viewer', 'transcriptViewerLogic']),
    props({} as TranscriptViewerLogicProps),
    actions({
        setFilter: (filter: TranscriptFilter) => ({ filter }),
        setSearch: (search: string) => ({ search }),
        showAllEntries: true,
    }),
    loaders(({ props }) => ({
        transcript: [
            null as StoredTranscript | null,
            {
                loadTranscript: () => readTranscript(props.organizationId),
            },
        ],
    })),
    reducers({
        transcriptError: [
            null as string | null,
            {
                loadTranscript: () => null,
                loadTranscriptFailure: (_, { error }) => error,
            },
        ],
        filter: ['focus' as TranscriptFilter, { setFilter: (_, { filter }) => filter }],
        search: ['', { setSearch: (_, { search }) => search }],
        showAll: [false, { showAllEntries: () => true }],
    }),
    selectors({
        entries: [(s) => [s.transcript], (transcript): TranscriptEntry[] => parseTranscript(transcript?.text ?? '')],
        counts: [
            (s) => [s.entries],
            (entries): Record<TranscriptFilter, number> =>
                Object.fromEntries(
                    TRANSCRIPT_FILTERS.map((filter) => [
                        filter,
                        entries.filter((entry: TranscriptEntry) => matchesFilter(entry.kind, filter)).length,
                    ])
                ) as Record<TranscriptFilter, number>,
        ],
        visibleEntries: [
            (s) => [s.entries, s.filter, s.search],
            (entries, filter, search): TranscriptEntry[] => {
                const query = search.trim().toLowerCase()
                return entries.filter(
                    (entry: TranscriptEntry) =>
                        matchesFilter(entry.kind, filter) && (!query || matchesSearch(entry, query))
                )
            },
        ],
        shownEntries: [
            (s) => [s.visibleEntries, s.showAll],
            (visibleEntries, showAll): TranscriptEntry[] =>
                showAll ? visibleEntries : visibleEntries.slice(0, ENTRIES_PER_PAGE),
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadTranscript()
    }),
])
