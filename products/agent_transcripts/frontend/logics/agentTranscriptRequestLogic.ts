export type agentTranscriptRequestLogicType = MakeLogicType<
    agentTranscriptRequestLogicValues,
    agentTranscriptRequestLogicActions,
    Record<string, any>,
    agentTranscriptRequestLogicMeta
>

/** Decides whether the floating request card shows, and records what people do with it. */
export const agentTranscriptRequestLogic = kea<agentTranscriptRequestLogicType>([
    path(['products', 'agent_transcripts', 'frontend', 'agentTranscriptRequestLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            agentTranscriptSubmissionLogic,
            ['currentOrganization', 'submission', 'submissionLoading'],
            router,
            ['location'],
        ],
        actions: [featureFlagLogic, ['setFeatureFlags'], agentTranscriptSubmissionLogic, ['loadSubmission']],
    })),
    actions({
        reportRequestShown: true,
        openRequest: true,
        dismissRequest: true,
        markDismissed: (organizationId: string, stage: AgentTranscriptRequestStage) => ({ organizationId, stage }),
    }),
    reducers({
        dismissedStages: [
            {} as Record<string, AgentTranscriptRequestStage>,
            // pinned: the persisted key comes from this logic's path, so moving the logic forgets every dismissal
            { persist: true },
            {
                markDismissed: (state, { organizationId, stage }) => ({ ...state, [organizationId]: stage }),
            },
        ],
    }),
    selectors({
        variant: [
            (s) => [s.featureFlags],
            (featureFlags: agentTranscriptRequestLogicValues['featureFlags']) =>
                agentTranscriptRequestVariant(featureFlags),
        ],
        stage: [
            (s) => [s.submission],
            (submission: agentTranscriptRequestLogicValues['submission']): AgentTranscriptRequestStage =>
                submission?.status === SubmissionStatusEnumApi.ChangesRequested ? 'changes_requested' : 'request',
        ],
        isOnSubmissionPage: [
            (s) => [s.location],
            (location: agentTranscriptRequestLogicValues['location']): boolean =>
                removeProjectIdIfPresent(location.pathname) === urls.agentTranscript(),
        ],
        isDismissed: [
            (s) => [s.dismissedStages, s.currentOrganization, s.stage],
            (
                dismissedStages: agentTranscriptRequestLogicValues['dismissedStages'],
                currentOrganization: agentTranscriptRequestLogicValues['currentOrganization'],
                stage: agentTranscriptRequestLogicValues['stage']
            ): boolean => {
                const dismissedStage = currentOrganization ? dismissedStages[currentOrganization.id] : undefined
                if (!dismissedStage) {
                    return false
                }

                return stage === 'request' || dismissedStage === 'changes_requested'
            },
        ],
        shouldShowRequest: [
            (s) => [s.variant, s.currentOrganization, s.submission, s.isDismissed, s.isOnSubmissionPage],
            (
                variant: agentTranscriptRequestLogicValues['variant'],
                currentOrganization: agentTranscriptRequestLogicValues['currentOrganization'],
                submission: agentTranscriptRequestLogicValues['submission'],
                isDismissed: agentTranscriptRequestLogicValues['isDismissed'],
                isOnSubmissionPage: agentTranscriptRequestLogicValues['isOnSubmissionPage']
            ): boolean =>
                !!variant &&
                !!currentOrganization &&
                !!submission &&
                STATUSES_THAT_ASK.includes(submission.status) &&
                !isDismissed &&
                !isOnSubmissionPage,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setFeatureFlags: () => {
            if (values.variant && !values.submission && !values.submissionLoading) {
                actions.loadSubmission()
            }
        },
        reportRequestShown: () => {
            // The card can hide and show again within a page load, for example around a visit to the page.
            if (cache.requestShownReported) {
                return
            }
            cache.requestShownReported = true

            posthog.capture(REQUEST_SHOWN_EVENT, { variant: values.variant, stage: values.stage })
        },
        openRequest: () => {
            posthog.capture(REQUEST_CLICKED_EVENT, { variant: values.variant, stage: values.stage })
        },
        dismissRequest: () => {
            const organizationId = values.currentOrganization?.id
            if (!organizationId) {
                return
            }

            actions.markDismissed(organizationId, values.stage)

            posthog.capture(REQUEST_DISMISSED_EVENT, { variant: values.variant, stage: values.stage })
        },
    })),
    afterMount(({ actions, values }) => {
        // Only an organization in the experiment is asked, so no one else pays for the request.
        if (values.variant) {
            actions.loadSubmission()
        }
    }),
])
