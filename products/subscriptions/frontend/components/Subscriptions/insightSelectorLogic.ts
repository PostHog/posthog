import { MakeLogicType, actions, connect, kea, path, props, propsChanged, reducers, selectors } from 'kea'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'

import { DashboardTile, TileGroupDisplay } from '~/types'

import type { DashboardTileGroupApi } from 'products/dashboards/frontend/generated/api.schemas'

import {
    InsightGroup,
    InsightGroupCheckboxState,
    getInsightGroupCheckboxState,
    getInsightGroups,
} from './insightGroupSelection'

// Keep in sync with MAX_INSIGHTS in products/subscriptions/backend/logic/subscription_utils.py
export const MAX_INSIGHTS = 20

export interface InsightSelectorLogicProps {
    tiles: DashboardTile[]
    selectedInsightIds?: number[]
    groups?: Record<string, DashboardTileGroupApi>
    groupDisplay?: TileGroupDisplay
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightSelectorLogicValues {
    featureFlags: FeatureFlagsSet
    groupDisplay: TileGroupDisplay | null
    groups: Record<string, DashboardTileGroupApi> | null
    insightGroupCheckboxStates: Record<string, InsightGroupCheckboxState>
    insightGroups: InsightGroup[]
    filteredTiles: DashboardTile[]
    insightTiles: DashboardTile[]
    searchTerm: string
    selectedInsightIds: number[]
    showSearch: boolean
    tiles: DashboardTile[]
    unavailableSelectedIds: number[]
    userHasInteracted: boolean
    validSelectedIds: number[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightSelectorLogicActions {
    setSearchTerm: (searchTerm: string) => {
        searchTerm: string
    }
    setSelectionInputs: (
        tiles: DashboardTile[],
        ids: number[],
        groups: Record<string, DashboardTileGroupApi> | undefined,
        groupDisplay: TileGroupDisplay | undefined
    ) => {
        groupDisplay: TileGroupDisplay | undefined
        groups: Record<string, DashboardTileGroupApi> | undefined
        ids: number[]
        tiles: DashboardTile[]
    }
    setUserHasInteracted: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightSelectorLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        validSelectedIds: (insightTiles: DashboardTile[], selectedInsightIds: number[]) => number[]
        unavailableSelectedIds: (validSelectedIds: number[], selectedInsightIds: number[]) => number[]
        insightTiles: (tiles: DashboardTile[]) => DashboardTile[]
        filteredTiles: (insightTiles: DashboardTile[], searchTerm: string) => DashboardTile[]
        showSearch: (insightTiles: DashboardTile[]) => boolean
        insightGroups: (
            tiles: DashboardTile[],
            featureFlags: FeatureFlagsSet,
            groups: Record<string, DashboardTileGroupApi> | null,
            groupDisplay: TileGroupDisplay | null
        ) => InsightGroup[]
        insightGroupCheckboxStates: (
            insightGroups: InsightGroup[],
            validSelectedIds: number[],
            groupDisplay: TileGroupDisplay | null
        ) => Record<string, InsightGroupCheckboxState>
    }
}

export type insightSelectorLogicType = MakeLogicType<
    insightSelectorLogicValues,
    insightSelectorLogicActions,
    InsightSelectorLogicProps,
    insightSelectorLogicMeta
>

export const insightSelectorLogic = kea<insightSelectorLogicType>([
    props({} as InsightSelectorLogicProps),
    path(['lib', 'components', 'Subscriptions', 'insightSelectorLogic']),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags']] })),

    actions({
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        setUserHasInteracted: true,
        setSelectionInputs: (
            tiles: DashboardTile[],
            ids: number[],
            groups: Record<string, DashboardTileGroupApi> | undefined,
            groupDisplay: TileGroupDisplay | undefined
        ) => ({ tiles, ids, groups, groupDisplay }),
    }),

    reducers(({ props }) => ({
        tiles: [props.tiles, { setSelectionInputs: (_, { tiles }) => tiles }],
        selectedInsightIds: [props.selectedInsightIds ?? [], { setSelectionInputs: (_, { ids }) => ids }],
        groups: [
            (props.groups ?? null) as Record<string, DashboardTileGroupApi> | null,
            { setSelectionInputs: (_, { groups }) => groups ?? null },
        ],
        groupDisplay: [
            (props.groupDisplay ?? null) as TileGroupDisplay | null,
            { setSelectionInputs: (_, { groupDisplay }) => groupDisplay ?? null },
        ],
        searchTerm: ['', { setSearchTerm: (_, { searchTerm }) => searchTerm }],
        userHasInteracted: [false, { setUserHasInteracted: () => true }],
    })),
    propsChanged(({ actions, props }, previousProps) => {
        if (
            props.selectedInsightIds !== previousProps.selectedInsightIds ||
            props.tiles !== previousProps.tiles ||
            props.groups !== previousProps.groups ||
            props.groupDisplay !== previousProps.groupDisplay
        ) {
            actions.setSelectionInputs(props.tiles, props.selectedInsightIds ?? [], props.groups, props.groupDisplay)
        }
    }),

    selectors({
        validSelectedIds: [
            (s) => [s.insightTiles, s.selectedInsightIds],
            (tiles: DashboardTile[], selectedIds: number[] = []): number[] => {
                const availableIds = new Set(tiles.map((tile) => tile.insight!.id))
                return selectedIds.filter((id) => availableIds.has(id))
            },
        ],
        unavailableSelectedIds: [
            (s) => [s.validSelectedIds, s.selectedInsightIds],
            (validIds: number[], selectedIds: number[] = []): number[] =>
                selectedIds.filter((id) => !validIds.includes(id)),
        ],
        insightTiles: [
            (s) => [s.tiles],
            (tiles: DashboardTile[]): DashboardTile[] =>
                ((tiles || []) as DashboardTile[])
                    .filter((tile): tile is DashboardTile => !!tile.insight && !tile.deleted && !tile.insight.deleted)
                    .sort(
                        (a, b) =>
                            (a.layouts?.sm?.y ?? 100) - (b.layouts?.sm?.y ?? 100) ||
                            (a.layouts?.sm?.x ?? 100) - (b.layouts?.sm?.x ?? 100)
                    ),
        ],
        filteredTiles: [
            (s) => [s.insightTiles, s.searchTerm],
            (insightTiles: DashboardTile[], searchTerm: string): DashboardTile[] => {
                if (!searchTerm.trim()) {
                    return insightTiles
                }
                const lowerSearch = searchTerm.toLowerCase()
                return insightTiles.filter((tile) => {
                    const name = tile.insight?.name || tile.insight?.derived_name || ''
                    return name.toLowerCase().includes(lowerSearch)
                })
            },
        ],
        showSearch: [(s) => [s.insightTiles], (insightTiles: DashboardTile[]) => insightTiles.length > 10],
        insightGroups: [
            (s) => [s.tiles, s.featureFlags, s.groups, s.groupDisplay],
            (
                tiles: DashboardTile[],
                featureFlags: FeatureFlagsSet,
                groups: Record<string, DashboardTileGroupApi> | null,
                groupDisplay: TileGroupDisplay | null
            ): InsightGroup[] =>
                // The dashboard only shows tabs and groups behind this flag, so the picker follows it.
                featureFlags[FEATURE_FLAGS.DASHBOARD_TILE_GROUP_SECTIONS]
                    ? getInsightGroups({
                          tiles: tiles || [],
                          groups: groups ?? undefined,
                          groupDisplay: groupDisplay ?? undefined,
                      })
                    : [],
        ],
        insightGroupCheckboxStates: [
            (s) => [s.insightGroups, s.validSelectedIds, s.groupDisplay],
            (
                insightGroups: InsightGroup[],
                validSelectedIds: number[],
                groupDisplay: TileGroupDisplay | null
            ): Record<string, InsightGroupCheckboxState> =>
                Object.fromEntries(
                    insightGroups.map((group) => [
                        group.key,
                        getInsightGroupCheckboxState({
                            group,
                            validSelectedIds,
                            maxInsights: MAX_INSIGHTS,
                            groupDisplay: groupDisplay ?? undefined,
                        }),
                    ])
                ),
        ],
    }),
])
