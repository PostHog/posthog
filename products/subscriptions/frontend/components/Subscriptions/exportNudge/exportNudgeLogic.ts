import { BreakPointFunction, MakeLogicType, connect, kea, listeners, path } from 'kea'
import { loaders } from 'kea-loaders'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import posthog from 'lib/posthog-typed'
import { userLogic } from 'scenes/userLogic'

import { dashboardsModel } from '~/models/dashboardsModel'
import { AvailableFeature, InsightShortId } from '~/types'

import {
    fetchHasSubscriptionForDashboard,
    fetchHasSubscriptionForInsight,
    fetchTeamSubscriptionCount,
} from 'products/subscriptions/frontend/components/Subscriptions/subscriptionQueries'
import { subscriptionsLogic } from 'products/subscriptions/frontend/components/Subscriptions/subscriptionsLogic'
import {
    SubscriptionBaseProps,
    isFreeTierCreateAtLimit,
} from 'products/subscriptions/frontend/components/Subscriptions/utils'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface exportNudgeLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    hasAvailableFeature: (feature: AvailableFeature, currentUsage?: number | undefined) => boolean // userLogic
    freeTierSubscriptionCount: number | null
    freeTierSubscriptionCountLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface exportNudgeLogicActions {
    loadFreeTierSubscriptionCount: (_?: unknown) => unknown
    loadFreeTierSubscriptionCountFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFreeTierSubscriptionCountSuccess: (
        freeTierSubscriptionCount: number,
        payload?: unknown
    ) => {
        freeTierSubscriptionCount: number
        payload?: unknown
    }
}

export type exportNudgeLogicType = MakeLogicType<exportNudgeLogicValues, exportNudgeLogicActions>

export const exportNudgeLogic = kea<exportNudgeLogicType>([
    path(['products', 'subscriptions', 'exportNudgeLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], userLogic, ['hasAvailableFeature']],
    })),
    loaders(() => ({
        // The `load` prefix puts this on initKea's ERROR_FILTER_ALLOW_LIST, so a failed background
        // check doesn't toast at a user who never asked for anything.
        freeTierSubscriptionCount: [
            null as number | null,
            {
                loadFreeTierSubscriptionCount: async (_?: unknown, breakpoint?: BreakPointFunction) =>
                    await fetchTeamSubscriptionCount(breakpoint),
            },
        ],
    })),
    listeners(() => ({
        loadFreeTierSubscriptionCountFailure: ({ error, errorObject }) => {
            // A failed count check silently excludes a free-tier user, so record it: the readout
            // cannot otherwise tell that apart from being at the limit.
            captureExportNudgeCheckFailed('limit', {
                error_name: errorObject?.name,
                error_status: errorObject?.status,
                error_message: error,
            })
        },
    })),
])

// Spelled out rather than interpolated, so the event a metric is configured against is greppable.
const NUDGE_SHOWN_EVENTS = {
    dashboard: 'dashboard export nudge shown',
    insight: 'insight export nudge shown',
} as const

// The offer is retired by one thing only, for either subject: the subject already having a
// subscription. Delete that subscription and the offer comes back, since the reason it was retired
// is gone. The repeat-view nudge keeps its own persisted suppression; this one does not share it.

/** What an export is of. Exports of anything else are never nudged. */
export type ExportNudgeSubject =
    | { kind: 'dashboard'; dashboardId: number }
    | { kind: 'insight'; insightShortId: InsightShortId }

/** A subject whose exporter cleared every eligibility check except the experiment flag. */
export interface ExportNudgeCandidate {
    subject: ExportNudgeSubject
    name: string | null
}

/**
 * Eligibility as far as it can be answered without a request. `unknown` means one of the
 * subscription queries still has to run.
 */
export type ExportNudgeLookup =
    | { status: 'eligible'; candidate: ExportNudgeCandidate }
    | { status: 'ineligible' }
    | { status: 'unknown' }

// Diagnostic event, shared by both experiments: the team-wide free-tier count is checked before any
// subject is in hand, so that failure carries no `kind` to split it by.
export function captureExportNudgeCheckFailed(
    step: 'limit' | 'check' | 'timeout' | 'toast-gone',
    properties: Record<string, unknown> = {}
): void {
    posthog.capture('export nudge check failed', { step, ...properties })
}

// Mounted on first use rather than from a caller's connect(), so exports of anything else don't pay
// for it. Left mounted afterwards so the free-tier count survives between exports.
function mountedExportNudgeLogic(): typeof exportNudgeLogic {
    if (!exportNudgeLogic.isMounted()) {
        exportNudgeLogic.mount()
    }
    return exportNudgeLogic
}

/** Identifies the subject on every nudge event, so each kind's funnel stands on its own. */
export function exportNudgeEventProperties(subject: ExportNudgeSubject): Record<string, string | number> {
    return subject.kind === 'dashboard'
        ? { kind: subject.kind, dashboard_id: subject.dashboardId }
        : { kind: subject.kind, insight_short_id: subject.insightShortId }
}

/** The subject as the subscriptions code addresses it: the mounted logic's key, and the CTA's url. */
export function subscriptionTargetFor(subject: ExportNudgeSubject): SubscriptionBaseProps {
    return subject.kind === 'dashboard'
        ? { dashboardId: subject.dashboardId }
        : { insightShortId: subject.insightShortId }
}

// The subscribe button on both scenes carries a count badge, which mounts subscriptionsLogic and
// loads the subject's subscriptions. Where that has already happened the export needs no request of
// its own. The badge only renders for teams that have the feature, so free-tier teams fall through.
// A load that failed is indistinguishable from an empty list here, since kea-loaders leaves the
// value at its [] default, so unlike the network path below, this one cannot fail closed.
function loadedSubscriptionCount(subject: ExportNudgeSubject): number | null {
    const mounted = subscriptionsLogic.findMounted(subscriptionTargetFor(subject))
    if (!mounted || mounted.values.subscriptionsLoading) {
        return null
    }
    return mounted.values.subscriptions.length
}

// Dashboards are named from the model the app already keeps loaded. Insights have no equivalent
// light-weight model, and pulling the insight scene in here would put it in every export surface's
// import graph, so the insight copy names no subject.
function subjectName(subject: ExportNudgeSubject): string | null {
    return subject.kind === 'dashboard'
        ? (dashboardsModel.findMounted()?.values.rawDashboards[subject.dashboardId]?.name ?? null)
        : null
}

/** Free-tier teams may only be offered a subscription while they have room under the cap. */
function subscriptionLimitStatus(): 'within' | 'exceeded' | 'unknown' {
    const { values } = mountedExportNudgeLogic()
    if (values.hasAvailableFeature(AvailableFeature.SUBSCRIPTIONS)) {
        return 'within'
    }
    if (values.freeTierSubscriptionCount === null) {
        return 'unknown'
    }
    return isFreeTierCreateAtLimit(values.freeTierSubscriptionCount) ? 'exceeded' : 'within'
}

/**
 * Answers eligibility from state the app already holds, so an export can put the offer in its toast
 * from the first frame. Stops short of the experiment flag, which is read when the nudge renders.
 */
export function lookUpExportNudge(subject: ExportNudgeSubject): ExportNudgeLookup {
    const limitStatus = subscriptionLimitStatus()
    if (limitStatus !== 'within') {
        return { status: limitStatus === 'unknown' ? 'unknown' : 'ineligible' }
    }

    const subscriptionCount = loadedSubscriptionCount(subject)
    if (subscriptionCount === null) {
        return { status: 'unknown' }
    }
    if (subscriptionCount > 0) {
        return { status: 'ineligible' }
    }
    return { status: 'eligible', candidate: { subject, name: subjectName(subject) } }
}

/**
 * The half of the check that needs the network, for an export whose scene had not already loaded the
 * answer. Runs alongside the export and folds into its toast once both have landed.
 */
export async function resolveExportNudgeEligibility(subject: ExportNudgeSubject): Promise<ExportNudgeCandidate | null> {
    const { values, asyncActions } = mountedExportNudgeLogic()
    if (!values.hasAvailableFeature(AvailableFeature.SUBSCRIPTIONS) && values.freeTierSubscriptionCount === null) {
        await asyncActions.loadFreeTierSubscriptionCount()
    }
    const limitStatus = subscriptionLimitStatus()
    if (limitStatus === 'unknown') {
        // Reachable without a failed request: a second export dispatches the same loader and
        // breakpoints this one, whose await then returns with the count still unresolved. Reported
        // because every other way the offer disappears reports a step, and this one fails closed.
        captureExportNudgeCheckFailed('limit', exportNudgeEventProperties(subject))
        return null
    }
    if (limitStatus !== 'within') {
        return null
    }

    const hasExistingSubscription = await fetchHasExistingSubscription(subject)
    if (hasExistingSubscription === null) {
        return null // fail closed on a broken check
    }
    if (hasExistingSubscription) {
        return null
    }

    return { subject, name: subjectName(subject) }
}

/**
 * Last gate, run as the nudge renders so an exposure is never reported for a toast nobody saw.
 * Returns whether this exporter is in the treatment.
 */
export function claimExportNudge(subject: ExportNudgeSubject): boolean {
    const { values } = mountedExportNudgeLogic()
    const flag =
        subject.kind === 'dashboard' ? FEATURE_FLAGS.DASHBOARD_EXPORT_NUDGE : FEATURE_FLAGS.INSIGHT_EXPORT_NUDGE
    // Reading the flag fires the exposure event, so it goes last, once every other check has passed.
    if (values.featureFlags[flag] !== 'test') {
        return false
    }

    posthog.capture(NUDGE_SHOWN_EVENTS[subject.kind], exportNudgeEventProperties(subject))
    return true
}

/** Whether this subject already has a subscription. null means the check itself failed. */
async function fetchHasExistingSubscription(subject: ExportNudgeSubject): Promise<boolean | null> {
    try {
        return subject.kind === 'dashboard'
            ? await fetchHasSubscriptionForDashboard(subject.dashboardId)
            : await fetchHasSubscriptionForInsight(subject.insightShortId)
    } catch (error: any) {
        captureExportNudgeCheckFailed('check', {
            ...exportNudgeEventProperties(subject),
            error_name: error?.name,
            error_status: error?.status,
            error_message: error?.message ?? String(error),
        })
        return null
    }
}
