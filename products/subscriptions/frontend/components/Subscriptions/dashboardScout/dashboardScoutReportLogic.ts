const RECENT_REPORTS_LIMIT = 5

/** The recent reports from a dashboard's scouts, reached from the dashboard's header. */
export const dashboardScoutReportLogic = kea<dashboardScoutReportLogicType>([
    props({} as DashboardScoutReportLogicProps),
    key((props) => props.dashboardId),
    path((key) => ['products', 'subscriptions', 'dashboardScout', 'dashboardScoutReportLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentProjectId'], organizationLogic, ['currentOrganization']],
    })),
    actions({
        openReports: true,
        closeReports: true,
    }),
    loaders(({ props, values }) => ({
        scouts: [
            null as SignalScoutConfigApi[] | null,
            {
                loadScouts: async () =>
                    await signalsScoutConfigList(String(values.currentProjectId), {
                        tags: dashboardScoutTag(props.dashboardId),
                    }),
            },
        ],
        reports: [
            null as SignalReportListApi[] | null,
            {
                loadReports: async () => {
                    const response = await signalsReportsList(String(values.currentProjectId), {
                        scout: (values.scouts ?? []).map((scout) => scout.skill_name).join(','),
                        ordering: '-updated_at',
                        limit: RECENT_REPORTS_LIMIT,
                    })
                    return response.results
                },
            },
        ],
    })),
    reducers({
        reportsOpen: [false, { openReports: () => true, closeReports: () => false }],
    }),
    selectors({
        latestReport: [
            (s) => [s.reports],
            (reports: SignalReportListApi[] | null): SignalReportListApi | null => reports?.[0] ?? null,
        ],
        latestReportScout: [
            (s) => [s.scouts, s.latestReport],
            (
                scouts: SignalScoutConfigApi[] | null,
                latestReport: SignalReportListApi | null
            ): SignalScoutConfigApi | null =>
                (scouts ?? []).find((scout: SignalScoutConfigApi) => scout.skill_name === latestReport?.scout_name) ??
                scouts?.[0] ??
                null,
        ],
    }),
    listeners(({ actions, props }) => ({
        openReports: () => {
            posthog.capture('dashboard scout reports opened', { dashboard_id: props.dashboardId })
        },
        loadScoutsSuccess: ({ scouts }) => {
            if (scouts?.length) {
                actions.loadReports()
            }
        },
        loadReportsSuccess: ({ reports }) => {
            if (reports?.length) {
                posthog.capture('dashboard scout reports available', {
                    dashboard_id: props.dashboardId,
                    report_id: reports[0].id,
                    report_count: reports.length,
                })
            }
        },
    })),
    afterMount(({ actions, values }) => {
        // Scouts need AI data processing approval, so other organizations make no request here.
        if (values.currentOrganization?.is_ai_data_processing_approved) {
            actions.loadScouts()
        }
    }),
])
