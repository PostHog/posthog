import { MakeLogicType, afterMount, connect, kea, listeners, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { organizationLogic } from 'scenes/organizationLogic'
import { teamLogic } from 'scenes/teamLogic'

import type { OrganizationType } from '~/types'

import { signalsScoutConfigList, signalsScoutMetadataGet } from 'products/signals/frontend/generated/api'
import type { ScoutMetadataApi, SignalScoutConfigApi } from 'products/signals/frontend/generated/api.schemas'

import { dashboardIdFromScoutTags } from './dashboardScout'

export interface DashboardScoutRow {
    scout: SignalScoutConfigApi
    dashboardId: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardScoutsListLogicValues {
    currentOrganization: OrganizationType | null // organizationLogic
    currentProjectId: number | string // teamLogic
    dashboardScoutRows: DashboardScoutRow[]
    scoutMetadata: ScoutMetadataApi | null
    scoutMetadataLoading: boolean
    taggedScouts: SignalScoutConfigApi[] | null
    taggedScoutsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardScoutsListLogicActions {
    loadScoutMetadata: () => any
    loadScoutMetadataFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadScoutMetadataSuccess: (
        scoutMetadata: ScoutMetadataApi,
        payload?: any
    ) => {
        scoutMetadata: ScoutMetadataApi
        payload?: any
    }
    loadTaggedScouts: () => any
    loadTaggedScoutsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTaggedScoutsSuccess: (
        taggedScouts: SignalScoutConfigApi[],
        payload?: any
    ) => {
        taggedScouts: SignalScoutConfigApi[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardScoutsListLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        dashboardScoutRows: (taggedScouts: any) => DashboardScoutRow[]
    }
}

export type dashboardScoutsListLogicType = MakeLogicType<
    dashboardScoutsListLogicValues,
    dashboardScoutsListLogicActions,
    Record<string, any>,
    dashboardScoutsListLogicMeta
>

/** Every scout in the project that was set up from a dashboard, for the subscriptions page. */
export const dashboardScoutsListLogic = kea<dashboardScoutsListLogicType>([
    path(['products', 'subscriptions', 'dashboardScout', 'dashboardScoutsListLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId'], organizationLogic, ['currentOrganization']],
    })),
    loaders(({ values }) => ({
        scoutMetadata: [
            null as ScoutMetadataApi | null,
            {
                loadScoutMetadata: async () => await signalsScoutMetadataGet(String(values.currentProjectId)),
            },
        ],
        taggedScouts: [
            null as SignalScoutConfigApi[] | null,
            {
                loadTaggedScouts: async () =>
                    await signalsScoutConfigList(String(values.currentProjectId), { tags: 'dashboards' }),
            },
        ],
    })),
    selectors({
        dashboardScoutRows: [
            (s) => [s.taggedScouts],
            (taggedScouts): DashboardScoutRow[] =>
                (taggedScouts ?? []).flatMap((scout: SignalScoutConfigApi) => {
                    const dashboardId = dashboardIdFromScoutTags(scout.tags)
                    return dashboardId === null ? [] : [{ scout, dashboardId }]
                }),
        ],
    }),
    listeners(({ actions }) => ({
        loadScoutMetadataSuccess: ({ scoutMetadata }) => {
            if (scoutMetadata?.enrolled) {
                actions.loadTaggedScouts()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        // Same reason as the modal: a project that cannot run scouts makes no scout request.
        if (values.currentOrganization?.is_ai_data_processing_approved) {
            actions.loadScoutMetadata()
        }
    }),
])
