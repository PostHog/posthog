export const dashboardScoutLogic = kea<dashboardScoutLogicType>([
    props({} as DashboardScoutLogicProps),
    key((props) => props.dashboardId),
    path((key) => ['products', 'subscriptions', 'dashboardScout', 'dashboardScoutLogic', key]),
    connect(() => ({
        values: [
            teamLogic,
            ['currentProjectId'],
            organizationLogic,
            ['currentOrganization'],
            featureFlagLogic,
            ['featureFlags'],
        ],
    })),
    actions({
        openSetup: true,
        closeSetup: true,
    }),
    forms(({ props, values, actions }) => ({
        scoutSetup: {
            defaults: DEFAULT_DASHBOARD_SCOUT_SETUP as DashboardScoutSetup,
            errors: ({ destination, postMode, postPrompt }) =>
                // kea-forms types the error of an object field as a map of its keys. The destination
                // is one control, so its error is one message for the whole field.
                ({
                    destination: hasSlackTarget(destination) ? undefined : 'Choose where in Slack the scout posts',
                    postPrompt:
                        postMode === 'custom' && !postPrompt.trim() ? 'Describe when the scout should post' : undefined,
                }) as unknown as DeepPartialMap<DashboardScoutSetup, ValidationErrorType>,
            submit: async (setup) => {
                const { destination } = setup
                if (destination === null || values.currentProjectId === null) {
                    return
                }
                try {
                    const scout = await signalsScoutCreate(
                        String(values.currentProjectId),
                        buildDashboardScoutPayload(props.dashboardId, props.dashboardName, { ...setup, destination })
                    )
                    posthog.capture('dashboard scout created', {
                        dashboard_id: props.dashboardId,
                        scout_skill_name: scout.skill.name,
                        cadence: setup.cadence,
                        post_mode: setup.postMode,
                        has_focus: setup.focus.trim().length > 0,
                        slack_target: destination.users?.length ? 'dm' : 'channel',
                    })
                    lemonToast.success('Scout created', {
                        button: {
                            label: 'View scout',
                            action: () => router.actions.push(urls.inboxScout(scout.skill.name)),
                        },
                    })
                    actions.resetScoutSetup()
                    actions.closeSetup()
                    actions.loadDashboardScouts()
                } catch (error) {
                    const apiError = error instanceof ApiError ? error : null
                    lemonToast.error(apiError?.detail ?? 'Could not create the scout. Try again in a moment.')
                    throw error
                }
            },
        },
    })),
    loaders(({ props, values }) => ({
        scoutMetadata: [
            null as ScoutMetadataApi | null,
            {
                loadScoutMetadata: async () => await signalsScoutMetadataGet(String(values.currentProjectId)),
            },
        ],
        dashboardScouts: [
            null as SignalScoutConfigApi[] | null,
            {
                loadDashboardScouts: async () =>
                    await signalsScoutConfigList(String(values.currentProjectId), {
                        tags: dashboardScoutTag(props.dashboardId),
                    }),
            },
        ],
    })),
    reducers({
        setupOpen: [
            false,
            {
                openSetup: () => true,
                closeSetup: () => false,
            },
        ],
    }),
    selectors({
        scoutsAvailable: [
            (s) => [s.currentOrganization, s.scoutMetadata],
            (currentOrganization: OrganizationType | null, scoutMetadata: ScoutMetadataApi | null): boolean =>
                !!currentOrganization?.is_ai_data_processing_approved && !!scoutMetadata?.enrolled,
        ],
        instructionsPreview: [
            (s) => [s.scoutSetup, (_, props) => props.dashboardId, (_, props) => props.dashboardName],
            (scoutSetup: DashboardScoutSetup, dashboardId, dashboardName): string =>
                renderDashboardScoutBody(dashboardId, dashboardName, scoutSetup),
        ],
        scoutOffered: [
            (s) => [s.scoutsAvailable, s.featureFlags],
            (scoutsAvailable: boolean, featureFlags: FeatureFlagsSet): boolean =>
                // Reading the flag fires the exposure event, so it goes last: a project that
                // could never see the offer does not count as exposed to the experiment.
                scoutsAvailable && featureFlags[FEATURE_FLAGS.DASHBOARD_SUBSCRIPTION_SCOUT] === 'test',
        ],
    }),
    listeners(({ actions, values, props }) => ({
        loadScoutMetadataSuccess: () => {
            if (!values.scoutsAvailable) {
                return
            }
            actions.loadDashboardScouts()
            if (values.scoutOffered) {
                posthog.capture('dashboard scout offer shown', { dashboard_id: props.dashboardId })
            }
        },
        openSetup: () => {
            posthog.capture('dashboard scout setup opened', { dashboard_id: props.dashboardId })
        },
    })),
    afterMount(({ actions, values }) => {
        // The scout endpoints are of no use to an organization that has not approved AI data
        // processing, so those projects make no extra request when the modal opens.
        if (values.currentOrganization?.is_ai_data_processing_approved) {
            actions.loadScoutMetadata()
        }
    }),
])
