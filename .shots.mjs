import { chromium } from 'playwright'
const [dir, tag] = process.argv.slice(2)
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1280, height: 760 }, deviceScaleFactor: 2 })
await p.goto('http://localhost:8010/login'); await p.fill('input[type=email]', 'test@posthog.com'); await p.click('button[type=submit]').catch(()=>{}); await p.waitForTimeout(800); await p.fill('input[type=password]', '12345678'); await p.click('button[type=submit]'); await p.waitForURL(u => !u.pathname.startsWith('/login'))
await p.addStyleTag({ content: '.DebugNotice, [class*=debug-bar], #debug-bar {display:none!important}' }).catch(()=>{})
await p.goto('http://localhost:8010/home'); await p.waitForTimeout(6000)
await p.screenshot({ path: `${dir}/${tag}-home.png` })
await p.click('[data-attr=today-rail-spaces]'); await p.waitForTimeout(3000)
await p.screenshot({ path: `${dir}/${tag}-spaces.png` })
await p.locator('aside a[href*="task="]').first().click(); await p.waitForTimeout(6000)
await p.screenshot({ path: `${dir}/${tag}-task.png` })
await b.close()
