-- Faithful subset of the production persons schema (rust/persons_migrations),
-- covering every table the merge path touches. Kept non-partitioned: partition
-- pruning affects constants, not the shape of the merge cost, and the composite
-- (team_id, person_id) FK below reproduces the per-row RI check the partitioned
-- schema pays on every moved mapping.

CREATE SEQUENCE IF NOT EXISTS posthog_person_id_seq;

CREATE TABLE posthog_person (
    id BIGINT NOT NULL DEFAULT nextval('posthog_person_id_seq') PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    properties_last_updated_at JSONB,
    properties_last_operation JSONB,
    properties JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_identified BOOLEAN NOT NULL DEFAULT false,
    uuid UUID NOT NULL,
    version BIGINT,
    is_user_id INTEGER,
    team_id INTEGER NOT NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    last_seen_at TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX posthog_person_team_uuid_idx ON posthog_person (team_id, uuid);
-- Enables the composite FK used by the partitioned production table.
CREATE UNIQUE INDEX posthog_person_team_id_id_idx ON posthog_person (team_id, id);

CREATE TABLE posthog_persondistinctid (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distinct_id VARCHAR(400) NOT NULL,
    version BIGINT,
    person_id BIGINT NOT NULL,
    team_id INTEGER NOT NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT posthog_persondistinctid_person_fk
        FOREIGN KEY (team_id, person_id) REFERENCES posthog_person (team_id, id)
);

CREATE INDEX posthog_persondistinctid_person_id_5d655bba ON posthog_persondistinctid (person_id);
CREATE UNIQUE INDEX unique_distinct_id_for_team ON posthog_persondistinctid (team_id, distinct_id);

CREATE TABLE posthog_cohortpeople (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER,
    cohort_id INTEGER NOT NULL,
    person_id BIGINT NOT NULL REFERENCES posthog_person (id)
);

CREATE INDEX posthog_coh_cohort__89c25f_idx ON posthog_cohortpeople (cohort_id, person_id);
CREATE INDEX posthog_cohortpeople_person_id_33da7d3f ON posthog_cohortpeople (person_id);

CREATE TABLE posthog_featureflaghashkeyoverride (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature_flag_key VARCHAR(400) NOT NULL,
    hash_key VARCHAR(400) NOT NULL,
    person_id BIGINT NOT NULL REFERENCES posthog_person (id),
    team_id INTEGER NOT NULL
);

CREATE UNIQUE INDEX unique_hash_key_for_user_team_feature_flag
    ON posthog_featureflaghashkeyoverride (team_id, person_id, feature_flag_key);
CREATE INDEX posthog_featureflaghashkeyoverride_person_id_7e517f7c
    ON posthog_featureflaghashkeyoverride (person_id);
