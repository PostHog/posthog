#!/usr/bin/env python
"""Make CORE_FILTER_DEFINITIONS_BY_GROUP accessible frontend-side.

Run via hogli: `hogli build:taxonomy-json`. `--check` is what ci-python.yml and
`hogli ci:preflight` call to fail on drift without writing.
"""
# ruff: noqa: T201

import sys
import json
import argparse
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
# Ahead of site-packages, so the repo's posthog wins over an installed one of the
# same name and the check cannot compare against a different taxonomy.
sys.path.insert(0, str(REPO_ROOT))

from posthog.taxonomy.taxonomy import CORE_FILTER_DEFINITIONS_BY_GROUP  # noqa: E402 — needs the sys.path line above

OUTPUT = REPO_ROOT / "frontend/src/taxonomy/core-filter-definitions-by-group.json"


def render() -> str:
    """The exact contents the generated file must hold.

    The write path and --check both go through this, so the two cannot disagree
    about the output.
    """
    with_comment = {
        "//": "THIS FILE IS AUTOGENERATED. DO NOT EDIT MANUALLY. To update: pnpm run taxonomy:build",
        **CORE_FILTER_DEFINITIONS_BY_GROUP,  # Unpack the dictionary to include its contents
    }
    return json.dumps(with_comment, indent=4, sort_keys=True)


def check() -> int:
    # Bytes, not text, so no newline translation can hide or invent a difference.
    on_disk = OUTPUT.read_bytes() if OUTPUT.exists() else b""
    if on_disk == render().encode():
        return 0
    # stdout, because ci:preflight reports `result.stdout or result.stderr`.
    print(f"{OUTPUT.relative_to(REPO_ROOT)} is out of date with posthog/taxonomy/taxonomy.py.")
    print("Run `hogli build:taxonomy-json` and commit the result.")
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the frontend-side taxonomy JSON.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if the file on disk differs from the taxonomy, without writing anything.",
    )
    args = parser.parse_args()
    if args.check:
        return check()
    # Do not add a formatter pass here. Nothing reformats render()'s output before it
    # reaches the file, so the output stays byte-stable and the taxonomy drift check in
    # ci-python.yml cannot flap. The other half of that guarantee is the ignorePatterns
    # entry in .oxfmtrc.json, which keeps lint-staged's `bin/hogli format:yaml` (oxfmt)
    # off this file. Keep both.
    OUTPUT.write_bytes(render().encode())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
