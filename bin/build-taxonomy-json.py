#!/usr/bin/env python
"""Make CORE_FILTER_DEFINITIONS_BY_GROUP accessible outside Python.

Emits the whole taxonomy for the frontend, and the `$ai_*` event property names
for the MCP server, which allowlists them in trace responses.

Run via hogli: `hogli build:taxonomy-json`. `--check` is what ci-python.yml and
`hogli ci:preflight` call to fail on drift without writing.
"""
# ruff: noqa: T201

import sys
import json
import argparse
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
# Ahead of site-packages, so the repo's posthog wins over an installed one of the
# same name and the check cannot compare against a different taxonomy.
sys.path.insert(0, str(REPO_ROOT))

from posthog.taxonomy.taxonomy import CORE_FILTER_DEFINITIONS_BY_GROUP  # noqa: E402 — needs the sys.path line above

OUTPUT = REPO_ROOT / "frontend/src/taxonomy/core-filter-definitions-by-group.json"
MCP_ALLOWLIST_OUTPUT = REPO_ROOT / "services/mcp/src/lib/trace-property-allowlist.generated.ts"


def render() -> str:
    """The exact contents the generated file must hold.

    The write path and --check both go through this, so the two cannot disagree
    about the output.
    """
    with_comment = {
        "//": "THIS FILE IS AUTOGENERATED. DO NOT EDIT MANUALLY. To update: pnpm run taxonomy:build",
        **CORE_FILTER_DEFINITIONS_BY_GROUP,  # Unpack the dictionary to include its contents
    }
    return json.dumps(with_comment, indent=4, sort_keys=True)


def render_mcp_allowlist() -> str:
    """The `$ai_*` event properties an MCP trace response may carry.

    `query-llm-trace` and `query-llm-traces-list` withhold every property the
    taxonomy does not define, so an application cannot hand a credential back to
    an agent through the event property bag. The rule cannot be a `$ai_` prefix
    test, because capture does not reserve the namespace.
    """
    names = sorted(name for name in CORE_FILTER_DEFINITIONS_BY_GROUP["event_properties"] if name.startswith("$ai_"))
    # oxfmt wants single quotes, so format by hand rather than with json.dumps and
    # keep the output byte-stable. A taxonomy name never needs escaping; assert it
    # so one that does fails the build instead of the TypeScript parse.
    for name in names:
        if "'" in name or "\\" in name:
            raise RuntimeError(f"unexpected character in property name: {name!r}")
    body = ",\n".join(f"    '{name}'" for name in names)
    return (
        "// THIS FILE IS AUTOGENERATED from posthog/taxonomy/taxonomy.py. DO NOT EDIT\n"
        "// MANUALLY. To update: pnpm run taxonomy:build\n"
        "//\n"
        "// Every other property of a trace event is withheld from MCP responses — see\n"
        "// services/mcp/src/lib/trace-redaction.ts.\n"
        "\n"
        "export const AI_TAXONOMY_EVENT_PROPERTIES = [\n"
        f"{body},\n"
        "] as const\n"
    )


def outputs() -> list[tuple[Path, str]]:
    return [(OUTPUT, render()), (MCP_ALLOWLIST_OUTPUT, render_mcp_allowlist())]


def read_bytes(path: Path) -> bytes:
    # Bytes, not text, so no newline translation can hide or invent a difference.
    return path.read_bytes() if path.exists() else b""


def check() -> int:
    stale = [path for path, contents in outputs() if read_bytes(path) != contents.encode()]
    if not stale:
        return 0
    for path in stale:
        # stdout, because ci:preflight reports `result.stdout or result.stderr`.
        print(f"{path.relative_to(REPO_ROOT)} is out of date with posthog/taxonomy/taxonomy.py.")
    print("Run `hogli build:taxonomy-json` and commit the result.")
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the frontend-side taxonomy JSON.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if the file on disk differs from the taxonomy, without writing anything.",
    )
    args = parser.parse_args()
    if args.check:
        return check()
    # Do not add a formatter pass here. Nothing reformats render()'s output before it
    # reaches the file, so the output stays byte-stable and the taxonomy drift check in
    # ci-python.yml cannot flap. The other half of that guarantee is the ignorePatterns
    # entry in .oxfmtrc.json, which keeps lint-staged's `bin/hogli format:yaml` (oxfmt)
    # off this file. Keep both.
    for path, contents in outputs():
        path.write_bytes(contents.encode())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
