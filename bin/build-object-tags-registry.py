#!/usr/bin/env python
"""Emit the agent object-tag kind registry for its TypeScript consumers.

The source of truth is ``posthog/object_tags/kinds.py``; Python
consumers import it directly. This generator carries the same registry to the
desktop packages and the web frontend, plus the kind list the rich-output
prompt teaches agents, so none of them can drift.

Run via hogli: `hogli build:object-tags`. `--check` is what ci-python.yml and
`hogli ci:preflight` call to fail on drift without writing.
"""
# ruff: noqa: T201

import sys
import json
import argparse
from collections.abc import Callable
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
# Ahead of site-packages, so the repo's posthog wins over an installed one of the
# same name and the check cannot compare against a different registry.
sys.path.insert(0, str(REPO_ROOT))

from posthog.object_tags.kinds import (  # noqa: E402 — needs the sys.path line above
    FALLBACK_OBJECT_KIND,
    OBJECT_KIND_ALIASES,
    OBJECT_KINDS,
    ObjectKindSpec,
)

HEADER = """\
// THIS FILE IS AUTOGENERATED by bin/build-object-tags-registry.py. DO NOT EDIT.
// Source of truth: posthog/object_tags/kinds.py — after editing it,
// run `hogli build:object-tags` and commit the result.
"""

DATA_INTERFACE = """\
export interface ObjectKindData {
  /** Human name of the kind, e.g. "Insight". */
  kindLabel: string;
  /** Product the object comes from, e.g. "Product analytics". */
  source: string;
  /**
   * Project-relative page template where "{id}" is the URL-encoded object id,
   * or null when the kind has no canonical page.
   */
  pathTemplate: string | null;
  /**
   * When set, the raw id must match for the kind to have a page at all
   * (e.g. flag pages resolve by numeric id only).
   */
  idPattern: string | null;
  /** display="block" renders as a full card on surfaces that support it. */
  block: boolean;
  /** The tag body is the object id itself rather than a label (hogql: the SQL). */
  idIsBody: boolean;
}
"""


def _entry(spec: ObjectKindSpec, indent: str) -> str:
    fields = [
        f"kindLabel: {json.dumps(spec.kind_label)}",
        f"source: {json.dumps(spec.source)}",
        f"pathTemplate: {json.dumps(spec.path_template)}",
        f"idPattern: {json.dumps(spec.id_pattern)}",
        f"block: {json.dumps(spec.block)}",
        f"idIsBody: {json.dumps(spec.id_is_body)}",
    ]
    body = "".join(f"{indent}  {field},\n" for field in fields)
    return "{\n" + body + indent + "}"


def render_registry_ts() -> str:
    kinds = "".join(f"  {name}: {_entry(spec, '  ')},\n" for name, spec in OBJECT_KINDS.items())
    aliases = "".join(f"  {json.dumps(alias)}: {json.dumps(kind)},\n" for alias, kind in OBJECT_KIND_ALIASES.items())
    return (
        HEADER
        + "\n"
        + DATA_INTERFACE
        + "\n"
        + "export const OBJECT_KIND_DATA = {\n"
        + kinds
        + "} satisfies Record<string, ObjectKindData>;\n"
        + "\n"
        + "export type ObjectKindName = keyof typeof OBJECT_KIND_DATA;\n"
        + "\n"
        + "/** Alternate tag names agents plausibly write, mapped to registry kinds. */\n"
        + "export const OBJECT_KIND_ALIASES: Record<string, string> = {\n"
        + aliases
        + "};\n"
        + "\n"
        + "/** Rendering fallback for a tag whose kind nobody registered. */\n"
        + f"export const FALLBACK_OBJECT_KIND_DATA: ObjectKindData = {_entry(FALLBACK_OBJECT_KIND, '')};\n"
    )


def render_prompt_kinds_ts() -> str:
    # hogql is taught by its own prompt bullet, not the kind list.
    names = ", ".join(name for name, spec in OBJECT_KINDS.items() if not spec.id_is_body)
    return (
        HEADER
        + "\n"
        + "/** The kind list the rich-output prompt teaches agents. */\n"
        + f"export const OBJECT_TAG_PROMPT_KIND_LIST = {json.dumps(names)};\n"
    )


OUTPUTS: dict[Path, Callable[[], str]] = {
    REPO_ROOT / "products/desktop/packages/core/src/inbox/objectKinds.generated.ts": render_registry_ts,
    REPO_ROOT / "products/desktop/packages/shared/src/objectTagKinds.generated.ts": render_prompt_kinds_ts,
    REPO_ROOT / "frontend/src/lib/components/AgentObjectTags/objectKinds.generated.ts": render_registry_ts,
}


def check() -> int:
    stale = []
    for path, render in OUTPUTS.items():
        # Bytes, not text, so no newline translation can hide or invent a difference.
        on_disk = path.read_bytes() if path.exists() else b""
        if on_disk != render().encode():
            stale.append(path)
    if not stale:
        return 0
    # stdout, because ci:preflight reports `result.stdout or result.stderr`.
    for path in stale:
        print(f"{path.relative_to(REPO_ROOT)} is out of date with posthog/object_tags/kinds.py.")
    print("Run `hogli build:object-tags` and commit the result.")
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the object-tag kind registry for TS consumers.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if any generated file differs from the registry, without writing anything.",
    )
    args = parser.parse_args()
    if args.check:
        return check()
    # Do not add a formatter pass here. Nothing reformats render()'s output before it
    # reaches the files, so the output stays byte-stable and the drift check cannot
    # flap. The other halves of that guarantee are the ignorePatterns entries in
    # .oxfmtrc.json (frontend copy) and the generated-files override in
    # products/desktop/biome.jsonc (desktop copies). Keep all of them.
    for path, render in OUTPUTS.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(render().encode())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
