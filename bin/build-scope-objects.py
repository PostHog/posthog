#!/usr/bin/env python3
"""Write the scope object lists from posthog/scopes.py to the frontend.

The script writes `frontend/src/lib/scopeObjects.generated.ts` with three lists:

- API_SCOPE_OBJECTS: every object in `APIScopeObject`, in the same order.
- INTERNAL_API_SCOPE_OBJECTS: objects that only the server mints.
- OAUTH_HIDDEN_SCOPE_OBJECTS: objects that a personal API key can carry but OAuth never advertises.

`posthog/scopes.py` is the only source of these lists. A hand-kept copy on the frontend can
miss a new object, and no check compares the two sides. The generated file removes that copy.
`frontend/src/lib/scopes.test.ts` then makes every object either appear in the key picker or
have a reason to stay out of it.

Run with hogli: `hogli build:openapi-scope-objects`. It also runs as part of `build:openapi`.
"""
# ruff: noqa: T201

from __future__ import annotations

import sys
import runpy
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCOPES_PY = REPO_ROOT / "posthog" / "scopes.py"
OUTPUT_TS = REPO_ROOT / "frontend" / "src" / "lib" / "scopeObjects.generated.ts"


def ts_list(names: list[str]) -> str:
    return "\n".join(f"    '{name}'," for name in names)


def main() -> int:
    # runpy loads the file by path. This does not run posthog/__init__.py, which imports Django.
    scopes_globals = runpy.run_path(str(SCOPES_PY))
    objects: list[str] = list(scopes_globals["API_SCOPE_OBJECTS"])
    internal: list[str] = sorted(scopes_globals["INTERNAL_API_SCOPE_OBJECTS"])
    hidden: list[str] = sorted(scopes_globals["OAUTH_HIDDEN_SCOPE_OBJECTS"])

    # oxfmt requires single quotes. The script formats the text itself, so the output is the
    # same on each run. An object name that needs escaping stops the build.
    for name in objects:
        if "'" in name or "\\" in name:
            raise RuntimeError(f"unexpected character in scope object: {name!r}")

    output = (
        "// AUTO-GENERATED by bin/build-scope-objects.py from posthog/scopes.py.\n"
        "// Regenerate with `hogli build:openapi`. Do not edit.\n"
        "\n"
        "// Every scope object, in the order of `APIScopeObject` in posthog/scopes.py.\n"
        "export const API_SCOPE_OBJECTS = [\n"
        f"{ts_list(objects)}\n"
        "] as const\n"
        "\n"
        "// Objects that only the server mints. A person can never grant them.\n"
        "export const INTERNAL_API_SCOPE_OBJECTS = [\n"
        f"{ts_list(internal)}\n"
        "] as const\n"
        "\n"
        "// Objects that a personal API key can carry but OAuth never advertises.\n"
        "export const OAUTH_HIDDEN_SCOPE_OBJECTS = [\n"
        f"{ts_list(hidden)}\n"
        "] as const\n"
    )

    existing = OUTPUT_TS.read_text() if OUTPUT_TS.exists() else None
    if existing != output:
        OUTPUT_TS.write_text(output)
        print(f"wrote {OUTPUT_TS} ({len(objects)} scope objects)")
    else:
        print(f"{OUTPUT_TS} already up to date ({len(objects)} scope objects)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
