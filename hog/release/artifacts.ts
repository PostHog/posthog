import type { Artifact, Manifest } from '../src/updates/manifest'
import { GITHUB_REPOSITORY, RELEASES_URL } from '../src/updates/release-urls'
import { binaryName, npmPackageName, TARGETS, type Target } from '../src/updates/targets'

export function releaseTag(version: string): string {
    return `hog/v${version}`
}

// Semver puts a prerelease after a hyphen, as in 0.1.0-alpha.3. Build metadata after `+` doesn't count.
export function isPrerelease(version: string): boolean {
    return version.split('+')[0]!.includes('-')
}

export function baseUrl(version: string): string {
    return `${RELEASES_URL}/v${version}/`
}

export function mirrorUrl(version: string): string {
    return `https://github.com/${GITHUB_REPOSITORY}/releases/download/${releaseTag(version)}/`
}

export function buildManifest(
    version: string,
    artifacts: Record<string, Artifact>,
    dates: { publishedAt: Date; buildDate: Date },
    minimumVersion?: string
): Manifest {
    return {
        schema: 1,
        name: 'hog',
        version,
        tag: releaseTag(version),
        prerelease: isPrerelease(version),
        publishedAt: dates.publishedAt.toISOString(),
        buildDate: dates.buildDate.toISOString(),
        ...(minimumVersion ? { minimumVersion } : {}),
        baseUrl: baseUrl(version),
        mirrorUrl: mirrorUrl(version),
        artifacts,
    }
}

export function sha256Sums(artifacts: Record<string, Artifact>): string {
    return (
        Object.values(artifacts)
            .map((artifact) => `${artifact.sha256}  ${artifact.file}`)
            .sort((a, b) => a.split('  ')[1]!.localeCompare(b.split('  ')[1]!))
            .join('\n') + '\n'
    )
}

export interface PackageJson {
    name: string
    version: string
    [key: string]: unknown
}

const NPM_COMMON = {
    license: 'MIT',
    homepage: 'https://posthog.com',
    repository: { type: 'git', url: 'git+https://github.com/PostHog/posthog.git', directory: 'hog' },
    bugs: { url: 'https://github.com/PostHog/posthog/issues' },
}

// npm, pnpm and bun read `os`, `cpu` and `libc`, so each machine downloads only its own package.
export function platformPackageJson(target: Target, version: string): PackageJson {
    return {
        name: npmPackageName(target),
        version,
        description: `The ${target.id} binary for hog, the PostHog command line. Install @posthog/hog instead.`,
        ...NPM_COMMON,
        os: [target.os],
        cpu: [target.cpu],
        ...(target.libc ? { libc: [target.libc] } : {}),
        files: [`bin/${binaryName(target)}`],
        preferUnplugged: true,
    }
}

export function wrapperPackageJson(version: string): PackageJson {
    return {
        name: '@posthog/hog',
        version,
        description: 'hog, the PostHog command line',
        ...NPM_COMMON,
        keywords: ['posthog', 'cli', 'analytics'],
        bin: { hog: 'bin/hog.cjs' },
        files: ['bin/hog.cjs'],
        engines: { node: '>=18' },
        optionalDependencies: Object.fromEntries(TARGETS.map((target) => [npmPackageName(target), version])),
    }
}

function formulaBlock(version: string, artifacts: Record<string, Artifact>, id: string, indent: string): string {
    const artifact = artifacts[id]
    if (!artifact) {
        throw new Error(`The Homebrew formula needs the ${id} artifact.`)
    }
    return [
        `${indent}url "${baseUrl(version)}${artifact.file}"`,
        `${indent}mirror "${mirrorUrl(version)}${artifact.file}"`,
        `${indent}sha256 "${artifact.sha256}"`,
    ].join('\n')
}

// Homebrew picks the block for the machine. Linux on Homebrew is glibc, so the musl builds stay out.
export function homebrewFormula(version: string, artifacts: Record<string, Artifact>): string {
    const block = (id: string): string => formulaBlock(version, artifacts, id, '      ')
    return `# Generated by hog/release/package.ts in PostHog/posthog. Each release overwrites it.
class Hog < Formula
  desc "PostHog command line"
  homepage "https://posthog.com"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${block('darwin-arm64')}
    end
    on_intel do
${block('darwin-x64')}
    end
  end

  on_linux do
    on_arm do
${block('linux-arm64')}
    end
    on_intel do
${block('linux-x64')}
    end
  end

  def install
    bin.install "hog"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/hog --version")
  end
end
`
}
