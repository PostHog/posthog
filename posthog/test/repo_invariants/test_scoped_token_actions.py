from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any

import pytest

from django.urls import URLPattern, URLResolver, get_resolver

from rest_framework.parsers import JSONParser
from rest_framework.request import Request
from rest_framework.test import APIRequestFactory

from posthog.permissions import ScopeBasePermission

BASELINE = Path(__file__).with_name("scoped_token_actions_baseline.txt")

# Actions that must reject scoped personal API keys and OAuth tokens on purpose.
# Key: "<module>.<ViewSet>.<action> <METHOD>". Value: why the action is session-only.
SESSION_ONLY_REASONS: dict[str, str] = {}

REGENERATE = (
    "Regenerate it with: PYTHONPATH=. DJANGO_SETTINGS_MODULE=posthog.settings TEST=1 python -c "
    "\"import sys, django; django.setup(); sys.path.insert(0, 'posthog/test/repo_invariants'); "
    'import test_scoped_token_actions as t; t.write_baseline()"'
)

_factory = APIRequestFactory()


def _routed_callbacks(patterns: list[URLPattern | URLResolver]) -> Iterator[Callable[..., Any]]:
    for pattern in patterns:
        if isinstance(pattern, URLResolver):
            yield from _routed_callbacks(pattern.url_patterns)
        elif getattr(pattern.callback, "cls", None) is not None and getattr(pattern.callback, "actions", None):
            yield pattern.callback


def _required_scopes(callback: Callable[..., Any], method: str) -> list[str] | None:
    # Build the view the way ViewSetMixin.as_view() does for a real request, so @action kwargs,
    # the action list mappings and dangerously_get_required_scopes all run as in production.
    # The request has no body, so a resolver that reads the payload falls back to its default.
    actions: dict[str, str] = callback.actions  # type: ignore[attr-defined]
    view = callback.cls(**callback.initkwargs)  # type: ignore[attr-defined]
    view.action_map = actions
    view.action = actions[method]
    view.args, view.kwargs, view.format_kwarg = (), {}, None
    view.request = Request(getattr(_factory, method)("/"), parsers=[JSONParser()])
    return ScopeBasePermission()._get_required_scopes(view.request, view)


def _scan() -> tuple[set[str], dict[str, str]]:
    unscoped: set[str] = set()
    resolver_errors: dict[str, str] = {}
    for callback in _routed_callbacks(get_resolver().url_patterns):
        viewset = callback.cls  # type: ignore[attr-defined]
        if getattr(viewset, "scope_object", None) in (None, "", "INTERNAL"):
            continue
        for method, action in callback.actions.items():  # type: ignore[attr-defined]
            key = f"{viewset.__module__}.{viewset.__qualname__}.{action} {method.upper()}"
            try:
                if not _required_scopes(callback, method):
                    unscoped.add(key)
            except Exception as error:
                resolver_errors[key] = repr(error)
    return unscoped, resolver_errors


def _read_baseline() -> set[str]:
    lines = BASELINE.read_text().splitlines() if BASELINE.exists() else []
    return {line for line in lines if line and not line.startswith("#")}


def write_baseline() -> None:
    unscoped, _ = _scan()
    header = "# Generated by write_baseline() in test_scoped_token_actions.py. Shrink it, never grow it.\n"
    BASELINE.write_text(header + "".join(f"{entry}\n" for entry in sorted(unscoped - SESSION_ONLY_REASONS.keys())))


@pytest.fixture(scope="module")
def scan() -> tuple[set[str], dict[str, str]]:
    return _scan()


def test_scope_resolvers_answer_for_every_routed_action(scan: tuple[set[str], dict[str, str]]) -> None:
    _, resolver_errors = scan
    assert not resolver_errors, (
        "dangerously_get_required_scopes raised for a request with no body, so this test cannot classify "
        f"these actions: {resolver_errors}. Make the resolver return None or a scope list for any request."
    )


def test_every_routed_action_resolves_a_token_scope(scan: tuple[set[str], dict[str, str]]) -> None:
    unscoped, _ = scan
    classified = _read_baseline() | SESSION_ONLY_REASONS.keys()

    new = sorted(unscoped - classified)
    assert not new, (
        f"These actions resolve to no API scope, so scoped personal API keys and OAuth tokens get a 403: {new}. "
        "Pass required_scopes to @action, list the action in scope_object_read_actions or "
        "scope_object_write_actions, or return a scope from dangerously_get_required_scopes. "
        "If the action must reject scoped tokens on purpose, add it to SESSION_ONLY_REASONS with the reason."
    )

    stale = sorted(classified - unscoped)
    assert not stale, f"These entries now resolve a scope or no longer exist: {stale}. {REGENERATE}"


def _route(viewset_name: str, action: str) -> Callable[..., Any]:
    for callback in _routed_callbacks(get_resolver().url_patterns):
        if callback.cls.__name__ == viewset_name and action in callback.actions.values():  # type: ignore[attr-defined]
            return callback
    raise AssertionError(f"{viewset_name}.{action} is not routed")


@pytest.mark.parametrize(
    ("viewset_name", "action", "method", "expected"),
    [
        ("LLMSkillViewSet", "get_by_name", "get", ["llm_skill:read"]),
        ("LLMSkillViewSet", "update_by_name", "patch", ["llm_skill:write"]),
        ("LLMSkillViewSet", "delete_file", "delete", ["llm_skill:write"]),
        ("QueryViewSet", "create", "post", ["query:read"]),
    ],
)
def test_scan_resolves_dynamic_scopes_per_method(
    viewset_name: str, action: str, method: str, expected: list[str]
) -> None:
    assert _required_scopes(_route(viewset_name, action), method) == expected
