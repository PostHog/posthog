from collections.abc import Iterator
from pathlib import Path
from typing import Any

from django.urls import URLPattern, URLResolver, get_resolver

from posthog.api.forbid_destroy_model import ForbidDestroyModel
from posthog.permissions import ScopeBasePermission

BASELINE = Path(__file__).with_name("scoped_token_actions_baseline.txt")
STANDARD_ACTIONS = (*ScopeBasePermission.read_actions, *ScopeBasePermission.write_actions)

REGENERATE = (
    'Regenerate it with: DJANGO_SETTINGS_MODULE=posthog.settings python -c "import django, sys; django.setup(); '
    "sys.path.insert(0, 'posthog/test/repo_invariants'); import test_scoped_token_actions as t; t.write_baseline()\""
)


def _routed_viewsets(patterns: list[URLPattern | URLResolver]) -> Iterator[type[Any]]:
    for pattern in patterns:
        if isinstance(pattern, URLResolver):
            yield from _routed_viewsets(pattern.url_patterns)
            continue
        viewset = getattr(pattern.callback, "cls", None)
        if viewset is not None and hasattr(viewset, "get_extra_actions"):
            yield viewset


def _actions_without_scope(viewset: type[Any]) -> list[str]:
    # Mirrors ScopeBasePermission._get_required_scopes: an action it resolves to no scope
    # returns 403 to every personal API key and OAuth token, whatever scopes the token has.
    scope_object = getattr(viewset, "scope_object", None)
    if not scope_object or scope_object == "INTERNAL":
        return []
    if getattr(viewset, "required_scopes", None) or hasattr(viewset, "dangerously_get_required_scopes"):
        return []

    read_actions = getattr(viewset, "scope_object_read_actions", ScopeBasePermission.read_actions)
    write_actions = getattr(viewset, "scope_object_write_actions", ScopeBasePermission.write_actions)
    declared = {*read_actions, *write_actions}

    missing = []
    for name in STANDARD_ACTIONS:
        method = getattr(viewset, name, None)
        if callable(method) and method is not ForbidDestroyModel.destroy and name not in declared:
            missing.append(name)
    for extra_action in viewset.get_extra_actions():
        if extra_action.__name__ not in declared and not extra_action.kwargs.get("required_scopes"):
            missing.append(extra_action.__name__)
    return missing


def _scan() -> set[str]:
    found: set[str] = set()
    for viewset in set(_routed_viewsets(get_resolver().url_patterns)):
        prefix = f"{viewset.__module__}.{viewset.__qualname__}"
        found.update(f"{prefix}.{action}" for action in _actions_without_scope(viewset))
    return found


def _read_baseline() -> set[str]:
    lines = BASELINE.read_text().splitlines() if BASELINE.exists() else []
    return {line for line in lines if line and not line.startswith("#")}


def write_baseline() -> None:
    header = "# Generated by write_baseline() in test_scoped_token_actions.py. Shrink it, never grow it.\n"
    BASELINE.write_text(header + "".join(f"{entry}\n" for entry in sorted(_scan())))


def test_every_routed_action_declares_a_token_scope() -> None:
    found = _scan()
    baseline = _read_baseline()

    new = sorted(found - baseline)
    assert not new, (
        f"These actions have no API scope, so scoped personal API keys and OAuth tokens get a 403: {new}. "
        "Pass required_scopes to @action, or list the action in scope_object_read_actions or "
        "scope_object_write_actions on the viewset. If the action must reject scoped tokens on purpose, "
        f"say why in the pull request. {REGENERATE}"
    )

    removed = sorted(baseline - found)
    assert not removed, (
        f"The baseline lists actions that now declare a scope or no longer exist: {removed}. {REGENERATE}"
    )
