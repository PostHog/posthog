# Archives the read_signature query tag in the v3 query_log_archive as lc_read_signature.
#
# The column reaches the OPS data table first, then the Buffer, then the writable Distributed tables
# on every cluster, and only then does the MV start writing it. A block that reaches a table before
# that table has the column would fail the insert.
#
# Each statement targets only the roles whose nodes hold the object, per the HCL goldens: an ALTER on a
# node without the table fails. The deployed cloud clusters and the multinode stack place the write path
# differently. The single-node stacks (local dev, hobby, tests) route every statement to NodeRole.ALL.
#
# The MV is replaced with CREATE OR REPLACE rather than ALTER ... MODIFY QUERY. MODIFY QUERY rewrites the
# MV's column list from the SELECT's output types, which drops the SimpleAggregateFunction types the HCL
# declares. CREATE OR REPLACE swaps the view in one step, so unlike DROP then CREATE it leaves no window,
# and no interrupted run, in which a node has no view archiving its query_log.
#
# The SQL is a copy of what query_log_archive.py produces for this migration, not an import: a later
# column added there would otherwise reach the MV before the migration that adds it to the tables.

