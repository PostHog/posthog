CREATE MATERIALIZED VIEW IF NOT EXISTS posthog.metrics2_input_to_metrics TO posthog.writable_metrics2 (team_id Int32, metric_name LowCardinality(String), series_fingerprint UInt64, resource_fingerprint UInt64, timestamp DateTime64(6), observed_timestamp DateTime64(6), original_expiry_timestamp DateTime64(6), service_name LowCardinality(String), metric_type LowCardinality(String), value Float64, count UInt64, histogram_bounds Array(Float64), histogram_counts Array(UInt64), trace_id String, span_id String, trace_flags Int32, has_labels Bool, unit LowCardinality(String), aggregation_temporality LowCardinality(String), is_monotonic Bool, instrumentation_scope String, _partition UInt32, _topic String, _offset UInt64) AS SELECT
  team_id,
  metric_name,
  series_fingerprint,
  resource_fingerprint,
  timestamp,
  observed_timestamp,
  original_expiry_timestamp,
  service_name,
  metric_type,
  value,
  count,
  histogram_bounds,
  histogram_counts,
  trace_id,
  span_id,
  trace_flags,
  has_labels,
  unit,
  aggregation_temporality,
  is_monotonic,
  instrumentation_scope,
  _partition,
  _topic,
  _offset
FROM posthog.metrics2_input;
