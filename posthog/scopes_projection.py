"""Project the OAuth scope universe from the posthog/scopes/ package into TypeScript.

Writes the same file to two trees: `services/mcp/src/lib/oauth-scopes.generated.ts`
for the MCP server and `frontend/src/lib/oauthScopes.generated.ts` for the web app.
Each carries four constants:

- OAUTH_SCOPES_SUPPORTED (the Python constant of the same name): the MCP server
  publishes RFC 9728 protected-resource metadata at
  `/.well-known/oauth-protected-resource`. Spec-compliant clients (e.g. Claude
  Code) read `scopes_supported` from there and pass every entry to the
  authorization server's `/oauth/authorize`. If the resource list contains a
  scope the AS does not recognize, sign-in fails with `?error=invalid_scope`,
  so this list must stay a subset of the AS's. The web app's consent screen
  expands a wildcard grant to the read scopes in this list when the server
  sends no computed list.
- OAUTH_SCOPES_HIDDEN: PAT-grantable scopes deliberately excluded from the
  list above (staff-only surfaces like `batch_import_support`). The MCP server
  uses this at runtime to gate tool discovery (`src/lib/staff-only-tools.ts`)
  and in tests to allow tools to require a non-advertised scope on purpose.
  The web app's scope pickers never show these objects, and scopes.test.ts
  exempts them from the picker rows and groups every other object needs.
- LEGACY_SCOPE_FALLBACKS: a new scope object mapped to the legacy one it split
  off. The MCP server applies it in `hasScope` (`src/lib/api.ts`), so a token
  carrying only the legacy scope still sees and calls tools that require the new one.
- RISKY_SCOPE_WARNINGS: what each risky scope lets a token do. The web app's scope pickers show it
  next to the scope, so every picker uses the same wording as the workload trust policy screens.

Generating both from the `posthog/scopes/` package keeps it the single
authority for scope classification; the TS side is a projection of it.

Registered in `tools/hogli-commands/hogli_commands/projections.py`; run
`hogli build:projections`.
"""

from __future__ import annotations

import sys
import json
import importlib
import importlib.util
from pathlib import Path
from types import ModuleType

SCOPES_PACKAGE = Path(__file__).resolve().parent / "scopes"
_STANDALONE_PACKAGE_NAME = "_posthog_scopes_standalone"
OUTPUTS = (
    "services/mcp/src/lib/oauth-scopes.generated.ts",
    "frontend/src/lib/oauthScopes.generated.ts",
)


def load_scopes_without_django() -> dict[str, ModuleType]:
    """Load every module of `posthog/scopes/` by file path, keyed by module name.

    `import posthog.scopes` runs `posthog/__init__.py`, which pulls in Celery and Django settings.
    Loading the package under a private name skips it, and the modules' relative imports resolve
    inside that private package. An import the package cannot satisfy from the standard library
    raises ImportError here, which fails the build loudly.
    """
    if _STANDALONE_PACKAGE_NAME not in sys.modules:
        spec = importlib.util.spec_from_file_location(
            _STANDALONE_PACKAGE_NAME,
            SCOPES_PACKAGE / "__init__.py",
            submodule_search_locations=[str(SCOPES_PACKAGE)],
        )
        assert spec is not None and spec.loader is not None
        package = importlib.util.module_from_spec(spec)
        sys.modules[_STANDALONE_PACKAGE_NAME] = package
        spec.loader.exec_module(package)
    return {
        path.stem: importlib.import_module(f"{_STANDALONE_PACKAGE_NAME}.{path.stem}")
        for path in sorted(SCOPES_PACKAGE.glob("*.py"))
        if path.stem != "__init__"
    }


def render_oauth_scopes() -> str:
    scopes = load_scopes_without_django()
    all_scopes: list[str] = list(scopes["oauth"].OAUTH_SCOPES_SUPPORTED)
    hidden_scopes: list[str] = sorted(scopes["exposure"].OAUTH_SCOPES_HIDDEN)
    legacy_fallbacks: dict[str, str] = scopes["checks"].LEGACY_SCOPE_FALLBACKS
    risky_scope_warnings: dict[str, str] = scopes["exposure"].RISKY_SCOPE_WARNINGS

    body = ",\n".join(f"    {json.dumps(s)}" for s in all_scopes)
    hidden_body = ",\n".join(f"    {json.dumps(s)}" for s in hidden_scopes)
    risky_body = "".join(
        f"    {json.dumps(scope)}: {json.dumps(warning)},\n" for scope, warning in sorted(risky_scope_warnings.items())
    )
    fallbacks_body = "".join(
        f"    [{json.dumps(new)}, {json.dumps(legacy)}],\n" for new, legacy in sorted(legacy_fallbacks.items())
    )
    output = (
        "// AUTO-GENERATED by posthog/scopes_projection.py from posthog/scopes/.\n"
        "// Regenerate with `hogli build:projections`. Do not edit.\n"
        "//\n"
        "// The OAuth scopes a client can request, from OAUTH_SCOPES_SUPPORTED in posthog/scopes/oauth.py.\n"
        "// The MCP server publishes this list as `scopes_supported` in its\n"
        "// protected-resource metadata (RFC 9728). The web app's consent screen\n"
        "// expands a wildcard grant to the read scopes in this list when the server\n"
        "// sends no computed list. The OAuth authorization server publishes this\n"
        "// list, plus AUTHORIZATION_SERVER_ONLY_SCOPES, at\n"
        "// `/.well-known/oauth-authorization-server`.\n"
        "// A scope here that the authorization server does not list makes a\n"
        "// spec-compliant client (e.g. Claude Code) fail sign-in with `invalid_scope`.\n"
        "\n"
        "export const OAUTH_SCOPES_SUPPORTED = [\n"
        f"{body},\n"
        "] as const\n"
        "\n"
        "export type OAuthScope = (typeof OAUTH_SCOPES_SUPPORTED)[number]\n"
        "\n"
        "// PAT-grantable but deliberately absent from OAUTH_SCOPES_SUPPORTED, so OAuth\n"
        "// clients can never request them (mirrors OAUTH_SCOPES_HIDDEN in posthog/scopes/exposure.py).\n"
        "// The MCP server shows a tool that requires one of these only to a staff user\n"
        "// whose personal API key carries it (plus `user:read` for the staff lookup);\n"
        "// `*` does not match. The web app's scope pickers never show these objects.\n"
        "export const OAUTH_SCOPES_HIDDEN = [\n"
        f"{hidden_body},\n"
        "] as const\n"
        "\n"
        "// A new scope object mapped to the legacy one it split off (mirrors LEGACY_SCOPE_FALLBACKS\n"
        "// in posthog/scopes/checks.py). While old tokens carry only the legacy scope, a held\n"
        "// `<legacy>:<action>` satisfies a required `<new>:<action>`.\n"
        "export const LEGACY_SCOPE_FALLBACKS: ReadonlyMap<string, string> = new Map([\n"
        f"{fallbacks_body}"
        "])\n"
        "\n"
        "// What each risky scope lets a token do (mirrors RISKY_SCOPE_WARNINGS in posthog/scopes/exposure.py).\n"
        "// Scope pickers show it next to the scope, so people add it with care.\n"
        "export const RISKY_SCOPE_WARNINGS: Readonly<Record<string, string>> = {\n"
        f"{risky_body}"
        "}\n"
    )
    return output


def render() -> dict[str, str]:
    output = render_oauth_scopes()
    return dict.fromkeys(OUTPUTS, output)
