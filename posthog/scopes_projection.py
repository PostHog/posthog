"""Project the OAuth scope classification in posthog/scopes.py into TypeScript.

Writes two files.

`services/mcp/src/lib/oauth-scopes.generated.ts`, the MCP server's view:

- OAUTH_SCOPES_SUPPORTED (from `get_oauth_scopes_supported()`): the MCP server
  publishes RFC 9728 protected-resource metadata at
  `/.well-known/oauth-protected-resource`. Spec-compliant clients (e.g. Claude
  Code) read `scopes_supported` from there and pass every entry to the
  authorization server's `/oauth/authorize`. If the resource list contains a
  scope the AS does not recognize, sign-in fails with `?error=invalid_scope`,
  so this list must stay a subset of the AS's.
- OAUTH_SCOPES_HIDDEN: PAT-grantable scopes deliberately excluded from the
  list above (staff-only surfaces like `batch_import_support`). The MCP server
  uses this at runtime to gate tool discovery (`src/lib/staff-only-tools.ts`)
  and in tests to allow tools to require a non-advertised scope on purpose.

`frontend/src/lib/scopes.generated.ts`, the web app's view:

- OAUTH_HIDDEN_SCOPE_OBJECTS and PRIVILEGED_SCOPE_OBJECTS: the scope objects
  the OAuth consent screen can never grant. The consent screen skips them when
  it expands a wildcard, and scopes.test.ts exempts them from the picker rows
  and groups that every other grantable object needs.

Generating all of it from `posthog/scopes.py` keeps that module the single
authority for scope classification; the TS side is a projection of it.

Registered in `tools/hogli-commands/hogli_commands/projections.py`; run
`hogli build:projections`.
"""

from __future__ import annotations

import runpy
from pathlib import Path
from typing import Any

SCOPES_PY = Path(__file__).resolve().parent / "scopes.py"
MCP_OUTPUT = "services/mcp/src/lib/oauth-scopes.generated.ts"
FRONTEND_OUTPUT = "frontend/src/lib/scopes.generated.ts"
# printWidth in .oxfmtrc.json. oxfmt collapses an array that fits on one line, and
# lint-staged formats every staged .ts file, so the renderer has to write that shape.
TS_PRINT_WIDTH = 120


def _load_scopes() -> dict[str, Any]:
    # runpy.run_path loads the file by filesystem path, bypassing the normal
    # import machinery and therefore posthog/__init__.py (which pulls in
    # Celery and Django settings). Any import that scopes.py doesn't satisfy
    # from stdlib will raise ImportError here, failing the build loudly.
    return runpy.run_path(str(SCOPES_PY))


def _ts_strings(values: list[str]) -> list[str]:
    # oxfmt enforces single quotes; format manually rather than json.dumps so
    # the generator output is byte-stable regardless of formatter rules. Scope
    # names are simple snake_case identifiers + colons and never need escaping,
    # but assert that to fail loudly if a scope ever does.
    for s in values:
        if "'" in s or "\\" in s:
            raise RuntimeError(f"unexpected character in scope name: {s!r}")
    return [f"'{s}'" for s in values]


def _ts_string_array(values: list[str]) -> str:
    return ",\n".join(f"    {s}" for s in _ts_strings(values))


def _ts_const_string_array(name: str, values: list[str]) -> str:
    one_line = f"export const {name} = [{', '.join(_ts_strings(values))}] as const"
    if len(one_line) <= TS_PRINT_WIDTH:
        return one_line + "\n"
    return f"export const {name} = [\n{_ts_string_array(values)},\n] as const\n"


def render_oauth_scopes(scopes_globals: dict[str, Any]) -> str:
    all_scopes: list[str] = scopes_globals["get_oauth_scopes_supported"]()
    hidden_scopes: list[str] = sorted(scopes_globals["OAUTH_SCOPES_HIDDEN"])
    body = _ts_string_array(all_scopes)
    hidden_body = _ts_string_array(hidden_scopes)
    output = (
        "// AUTO-GENERATED by posthog/scopes_projection.py from posthog/scopes.py.\n"
        "// Regenerate with `hogli build:projections`. Do not edit.\n"
        "//\n"
        "// Published as `scopes_supported` in MCP protected-resource metadata\n"
        "// (RFC 9728). The OAuth authorization server publishes the same list\n"
        "// from get_oauth_scopes_supported() at `/.well-known/oauth-authorization-server`.\n"
        "// Keeping them aligned is what stops spec-compliant clients (e.g. Claude\n"
        "// Code) from hitting `invalid_scope` at sign-in.\n"
        "\n"
        "export const OAUTH_SCOPES_SUPPORTED = [\n"
        f"{body},\n"
        "] as const\n"
        "\n"
        "export type OAuthScope = (typeof OAUTH_SCOPES_SUPPORTED)[number]\n"
        "\n"
        "// PAT-grantable but deliberately absent from OAUTH_SCOPES_SUPPORTED, so OAuth\n"
        "// clients can never request them (mirrors OAUTH_SCOPES_HIDDEN in posthog/scopes.py).\n"
        "// Tools requiring one of these only surface for staff users whose personal API key\n"
        "// explicitly carries it (plus `user:read` for the staff lookup); `*` does not match.\n"
        "export const OAUTH_SCOPES_HIDDEN = [\n"
        f"{hidden_body},\n"
        "] as const\n"
    )
    return output


def render_frontend_scopes(scopes_globals: dict[str, Any]) -> str:
    hidden_objects: list[str] = sorted(scopes_globals["OAUTH_HIDDEN_SCOPE_OBJECTS"])
    privileged_objects: list[str] = sorted({scope.split(":")[0] for scope in scopes_globals["PRIVILEGED_SCOPES"]})
    return (
        "// AUTO-GENERATED by posthog/scopes_projection.py from posthog/scopes.py.\n"
        "// Regenerate with `hogli build:projections`. Do not edit.\n"
        "\n"
        "// Pasteable into a personal API key, but never advertised to OAuth clients\n"
        "// (mirrors OAUTH_HIDDEN_SCOPE_OBJECTS in posthog/scopes.py). The pickers never\n"
        "// show these objects, so they need no row and no group in lib/scopes.tsx.\n"
        f"{_ts_const_string_array('OAUTH_HIDDEN_SCOPE_OBJECTS', hidden_objects)}"
        "\n"
        "// Only PostHog staff can grant these to an OAuth app (mirrors PRIVILEGED_SCOPES\n"
        "// in posthog/scopes.py), so a wildcard grant must not expand to them.\n"
        f"{_ts_const_string_array('PRIVILEGED_SCOPE_OBJECTS', privileged_objects)}"
    )


def render() -> dict[str, str]:
    scopes_globals = _load_scopes()
    return {
        MCP_OUTPUT: render_oauth_scopes(scopes_globals),
        FRONTEND_OUTPUT: render_frontend_scopes(scopes_globals),
    }
