"""Project the OAuth scope universe from posthog/scopes.py into TypeScript.

Writes the same file to two trees: `services/mcp/src/lib/oauth-scopes.generated.ts`
for the MCP server and `frontend/src/lib/oauthScopes.generated.ts` for the web app.
Each carries two constants:

- OAUTH_SCOPES_SUPPORTED (from `get_oauth_scopes_supported()`): the MCP server
  publishes RFC 9728 protected-resource metadata at
  `/.well-known/oauth-protected-resource`. Spec-compliant clients (e.g. Claude
  Code) read `scopes_supported` from there and pass every entry to the
  authorization server's `/oauth/authorize`. If the resource list contains a
  scope the AS does not recognize, sign-in fails with `?error=invalid_scope`,
  so this list must stay a subset of the AS's. The web app's consent screen
  expands a wildcard grant to the read scopes in this list when the server
  sends no computed list.
- OAUTH_SCOPES_HIDDEN: PAT-grantable scopes deliberately excluded from the
  list above (staff-only surfaces like `batch_import_support`). The MCP server
  uses this at runtime to gate tool discovery (`src/lib/staff-only-tools.ts`)
  and in tests to allow tools to require a non-advertised scope on purpose.
  The web app's scope pickers never show these objects, and scopes.test.ts
  exempts them from the picker rows and groups every other object needs.

Generating both from `posthog/scopes.py` keeps that module the single
authority for scope classification; the TS side is a projection of it.

Registered in `tools/hogli-commands/hogli_commands/projections.py`; run
`hogli build:projections`.
"""

from __future__ import annotations

import json
import runpy
from pathlib import Path

SCOPES_PY = Path(__file__).resolve().parent / "scopes.py"
OUTPUTS = (
    "services/mcp/src/lib/oauth-scopes.generated.ts",
    "frontend/src/lib/oauthScopes.generated.ts",
)


def render_oauth_scopes() -> str:
    # runpy.run_path loads the file by filesystem path, bypassing the normal
    # import machinery and therefore posthog/__init__.py (which pulls in
    # Celery and Django settings). Any import that scopes.py doesn't satisfy
    # from stdlib will raise ImportError here, failing the build loudly.
    scopes_globals = runpy.run_path(str(SCOPES_PY))
    all_scopes: list[str] = scopes_globals["get_oauth_scopes_supported"]()
    hidden_scopes: list[str] = sorted(scopes_globals["OAUTH_SCOPES_HIDDEN"])

    body = ",\n".join(f"    {json.dumps(s)}" for s in all_scopes)
    hidden_body = ",\n".join(f"    {json.dumps(s)}" for s in hidden_scopes)
    output = (
        "// AUTO-GENERATED by posthog/scopes_projection.py from posthog/scopes.py.\n"
        "// Regenerate with `hogli build:projections`. Do not edit.\n"
        "//\n"
        "// The OAuth scopes a client can request, from get_oauth_scopes_supported().\n"
        "// The MCP server publishes this list as `scopes_supported` in its\n"
        "// protected-resource metadata (RFC 9728). The web app's consent screen\n"
        "// expands a wildcard grant to the read scopes in this list when the server\n"
        "// sends no computed list. The OAuth authorization server publishes the same\n"
        "// list at `/.well-known/oauth-authorization-server`. If the lists differ, a\n"
        "// spec-compliant client (e.g. Claude Code) fails sign-in with `invalid_scope`.\n"
        "\n"
        "export const OAUTH_SCOPES_SUPPORTED = [\n"
        f"{body},\n"
        "] as const\n"
        "\n"
        "export type OAuthScope = (typeof OAUTH_SCOPES_SUPPORTED)[number]\n"
        "\n"
        "// PAT-grantable but deliberately absent from OAUTH_SCOPES_SUPPORTED, so OAuth\n"
        "// clients can never request them (mirrors OAUTH_SCOPES_HIDDEN in posthog/scopes.py).\n"
        "// The MCP server shows a tool that requires one of these only to a staff user\n"
        "// whose personal API key carries it (plus `user:read` for the staff lookup);\n"
        "// `*` does not match. The web app's scope pickers never show these objects.\n"
        "export const OAUTH_SCOPES_HIDDEN = [\n"
        f"{hidden_body},\n"
        "] as const\n"
    )
    return output


def render() -> dict[str, str]:
    output = render_oauth_scopes()
    return dict.fromkeys(OUTPUTS, output)
