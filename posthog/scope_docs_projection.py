"""Project the scope declarations in `posthog/scope_docs.py` into TypeScript for the web app.

The scope pickers read each scope object's name and description from the generated file, so the
web app keeps no copy of them.

The projection runner has no Django app registry, so this finds product declarations on disk.
`get_scope_docs()` finds them through the installed apps instead, and
posthog/test/repo_invariants/test_scope_docs.py checks that both find the same modules.

Registered in `tools/hogli-commands/hogli_commands/projections.py`; run `hogli build:projections`.
"""

import json
import importlib
from pathlib import Path

from posthog.scope_docs import SCOPE_GROUPS, ScopeDoc, collect_scope_docs
from posthog.scopes import PRIVILEGED_SCOPES

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = "frontend/src/lib/scopeDocs.generated.ts"


def product_scope_module_names() -> list[str]:
    return sorted(
        f"products.{path.parent.parent.name}.backend.scopes"
        for path in (REPO_ROOT / "products").glob("*/backend/scopes.py")
    )


def _render_doc(doc: ScopeDoc) -> str:
    fields = [
        f"name: {json.dumps(doc.name)}",
        f"plural: {json.dumps(doc.plural)}",
        f"description: {json.dumps(doc.description)}",
        f"group: {json.dumps(doc.group)}",
        f"actions: {json.dumps(list(doc.actions))}",
    ]
    if doc.docs_url:
        fields.append(f"docsUrl: {json.dumps(doc.docs_url)}")
    if doc.organization_wide:
        fields.append("organizationWide: true")
    if any(f"{doc.object}:{action}" in PRIVILEGED_SCOPES for action in doc.actions):
        fields.append("privileged: true")
    if doc.write_requires:
        requirement = {"scope": doc.write_requires.scope, "reason": doc.write_requires.reason}
        fields.append(f"writeRequires: {json.dumps(requirement)}")
    body = "".join(f"        {field},\n" for field in fields)
    return f"    {json.dumps(doc.object)}: {{\n{body}    }},\n"


def render_scope_docs() -> str:
    product_declarations = [
        getattr(importlib.import_module(name), "SCOPE_DOCS", ()) for name in product_scope_module_names()
    ]
    docs = collect_scope_docs(product_declarations)
    docs_body = "".join(_render_doc(doc) for doc in docs.values())
    return (
        "// AUTO-GENERATED by posthog/scope_docs_projection.py from the ScopeDoc declarations.\n"
        "// Regenerate with `hogli build:projections`. Do not edit.\n"
        "\n"
        "export type ScopeObjectDoc = {\n"
        "    name: string\n"
        "    plural: string\n"
        "    description: string\n"
        "    group: string\n"
        "    actions: ('read' | 'write')[]\n"
        "    docsUrl?: string\n"
        "    organizationWide?: true\n"
        "    // Only an admin-driven path grants it (PRIVILEGED_SCOPES in posthog/scopes.py).\n"
        "    privileged?: true\n"
        "    // A scope that writing this object also needs, and why.\n"
        "    writeRequires?: { scope: string; reason: string }\n"
        "}\n"
        "\n"
        "// The product areas pickers group scope objects under, in display order.\n"
        f"export const SCOPE_GROUPS: readonly string[] = {json.dumps(list(SCOPE_GROUPS))}\n"
        "\n"
        "// What each exposed scope object is for, keyed by scope object.\n"
        "export const SCOPE_DOCS: Readonly<Record<string, ScopeObjectDoc>> = {\n"
        f"{docs_body}"
        "}\n"
    )


def render() -> dict[str, str]:
    return {OUTPUT: render_scope_docs()}
