"""Make CORE_FILTER_DEFINITIONS_BY_GROUP accessible outside Python.

Emits the whole taxonomy for the frontend, and the `$ai_*` event property names
for the MCP server, which allowlists them in trace responses.

Registered in `tools/hogli-commands/hogli_commands/projections.py`; run
`hogli build:projections`.
"""

import json

from posthog.taxonomy.taxonomy import CORE_FILTER_DEFINITIONS_BY_GROUP

OUTPUT = "frontend/src/taxonomy/core-filter-definitions-by-group.json"
MCP_ALLOWLIST_OUTPUT = "services/mcp/src/lib/trace-property-allowlist.generated.ts"


def render_core_filter_definitions() -> str:
    with_comment = {
        "//": "THIS FILE IS AUTOGENERATED. DO NOT EDIT MANUALLY. To update: hogli build:projections",
        **CORE_FILTER_DEFINITIONS_BY_GROUP,  # Unpack the dictionary to include its contents
    }
    return json.dumps(with_comment, indent=4, sort_keys=True)


def render_mcp_allowlist() -> str:
    """The `$ai_*` event properties an MCP trace response may carry.

    `query-llm-trace` and `query-llm-traces-list` withhold every property the
    taxonomy does not define, so an application cannot hand a credential back to
    an agent through the event property bag. The rule cannot be a `$ai_` prefix
    test, because capture does not reserve the namespace.
    """
    names = sorted(name for name in CORE_FILTER_DEFINITIONS_BY_GROUP["event_properties"] if name.startswith("$ai_"))
    body = ",\n".join(f"    {json.dumps(name)}" for name in names)
    return (
        "// THIS FILE IS AUTOGENERATED from posthog/taxonomy/taxonomy.py. DO NOT EDIT\n"
        "// MANUALLY. To update: hogli build:projections\n"
        "//\n"
        "// Every other property of a trace event is withheld from MCP responses — see\n"
        "// services/mcp/src/lib/trace-redaction.ts.\n"
        "\n"
        "export const AI_TAXONOMY_EVENT_PROPERTIES = [\n"
        f"{body},\n"
        "] as const\n"
    )


def render() -> dict[str, str]:
    return {OUTPUT: render_core_filter_definitions(), MCP_ALLOWLIST_OUTPUT: render_mcp_allowlist()}
