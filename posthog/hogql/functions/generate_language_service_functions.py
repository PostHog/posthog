import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO_ROOT))

from posthog.hogql.functions.mapping import ALL_EXPOSED_FUNCTION_NAMES  # noqa: E402

OUTPUT_PATH = REPO_ROOT / "services/hogql-language-service/internal/completion/functions.go"


def render() -> str:
    names = sorted(set(ALL_EXPOSED_FUNCTION_NAMES))
    lines = [" ".join(names[index : index + 20]) for index in range(0, len(names), 20)]
    body = "\n".join(lines)
    return f"""// Code generated by posthog/hogql/functions/generate_language_service_functions.py; DO NOT EDIT.

package completion

import "strings"

var hogQLFunctions = strings.Fields(`
{body}
`)
"""


def main() -> None:
    OUTPUT_PATH.write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    main()
