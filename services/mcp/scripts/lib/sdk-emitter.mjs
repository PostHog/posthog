import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { format } from 'oxfmt'
import ts from 'typescript'

import { runOrvalParallel } from '../../../../tools/openapi-codegen/src/orval.mjs'
import { SdkTypeRegistry } from './sdk-type-registry.mjs'

const banner = '// Generated by hogli build:openapi-sdk. Edit the OpenAPI schema or MCP YAML instead.\n'

export function kebabCase(value) {
    return value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
}

function jsdoc(text) {
    return `/**\n${text
        .replace(/\*\//g, '* /')
        .split('\n')
        .map((line) => ` * ${line}`)
        .join('\n')}\n */`
}

function modelDescriptions(value) {
    if (!value || typeof value !== 'object') {
        return
    }
    // Permit additive API fields at runtime without inventing a public index signature for a known object.
    if (value.additionalProperties !== false && Object.keys(value.properties ?? {}).length) {
        delete value.additionalProperties
    }
    if (typeof value['x-source-description'] === 'string') {
        value.description = `${value.description}\n\n@sourceDescription ${value['x-source-description']}`
    }
    if (typeof value.description === 'string') {
        value.description = value.description.replace(/\*\//g, '* /')
    }
    for (const child of Object.values(value)) {
        modelDescriptions(child)
    }
}

function explicitInterfaces(source) {
    const parsed = ts.createSourceFile('models.ts', source, ts.ScriptTarget.Latest, true)
    const replacements = []
    const names = []
    for (const statement of parsed.statements) {
        if (!statement.name) {
            continue
        }
        const name = statement.name.text
        if (name.startsWith('JsonValue') || name === 'JsonObject' || name === 'ResponseMeta') {
            replacements.push({ start: statement.getFullStart(), end: statement.end, value: '' })
            continue
        }
        names.push(name)
        let variant = 0
        const interfaces = []
        const rewrite = (container, skipRoot = false) => {
            const edits = []
            const visit = (node) => {
                if (ts.isTypeLiteralNode(node) && !(skipRoot && node === container)) {
                    const nestedName = `${name}Variant${++variant}`
                    const declaration = rewrite(node, true)
                    interfaces.push(`export interface ${nestedName} ${declaration}`)
                    names.push(nestedName)
                    edits.push({
                        start: node.getStart(parsed) - container.getStart(parsed),
                        end: node.end - container.getStart(parsed),
                        value: nestedName,
                    })
                    return
                }
                ts.forEachChild(node, visit)
            }
            visit(container)
            let text = container.getText(parsed)
            for (const { start, end, value } of edits.sort((a, b) => b.start - a.start)) {
                text = text.slice(0, start) + value + text.slice(end)
            }
            return text
        }
        if (ts.isTypeAliasDeclaration(statement) && ts.isTypeLiteralNode(statement.type)) {
            replacements.push({
                start: statement.getStart(),
                end: statement.end,
                value: `export interface ${name} ${rewrite(statement.type, true)}\n${interfaces.join('\n')}`,
            })
        } else {
            const value = rewrite(statement)
            if (interfaces.length) {
                replacements.push({
                    start: statement.getStart(),
                    end: statement.end,
                    value: `${value}\n${interfaces.join('\n')}`,
                })
            }
        }
    }
    for (const { start, end, value } of replacements.sort((a, b) => b.start - a.start)) {
        source = source.slice(0, start) + value + source.slice(end)
    }
    // Unconstrained JSON leaves have a concrete recursive contract, even when Orval emits unknown.
    const typed = ts.createSourceFile('models.ts', source, ts.ScriptTarget.Latest, true)
    const unknowns = []
    const visit = (node) => {
        if (node.kind === ts.SyntaxKind.UnknownKeyword) {
            unknowns.push({ start: node.getStart(typed), end: node.end })
        }
        ts.forEachChild(node, visit)
    }
    visit(typed)
    for (const { start, end } of unknowns.sort((a, b) => b.start - a.start)) {
        source = source.slice(0, start) + 'JsonValue' + source.slice(end)
    }
    return { source, names: [...new Set(names)] }
}

function tsv(columns, rows) {
    const cell = (value) => String(value ?? '').replace(/[\t\r\n]+/g, ' ')
    return (
        [columns.join('\t'), ...rows.map((row) => columns.map((column) => cell(row[column])).join('\t'))].join('\n') +
        '\n'
    )
}

export async function emitSdk(operations, outputDir, manifest) {
    const { $schema, overrides, ignorePatterns, ...formatOptions } = JSON.parse(
        await fs.readFile(new URL('../../../../.oxfmtrc.json', import.meta.url), 'utf8')
    )
    const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'posthog-sdk-'))
    try {
        const { schemas } = new SdkTypeRegistry(operations).merge()
        modelDescriptions(schemas)
        const input = path.join(temporary, 'api.json')
        await fs.writeFile(
            input,
            JSON.stringify({
                openapi: '3.1.0',
                info: { title: 'PostHog SDK', version: '1' },
                paths: {},
                components: { schemas },
            })
        )
        const [result] = await runOrvalParallel([
            {
                label: 'SDK registry',
                config: {
                    input,
                    output: {
                        target: path.join(temporary, 'api.ts'),
                        mode: 'split',
                        client: 'fetch',
                        prettier: false,
                        override: {
                            header: () => [],
                            enumGenerationType: 'union',
                            fetch: { includeHttpResponseReturnType: false },
                        },
                    },
                },
            },
        ])
        if (result.status === 'rejected') {
            throw result.reason
        }
        const raw = await fs.readFile(path.join(temporary, 'api.schemas.ts'), 'utf8')
        const { source, names } = explicitInterfaces(raw)
        const generated = path.join(outputDir, 'src/generated')
        await fs.mkdir(generated, { recursive: true })
        const categories = new Map()
        const records = []
        for (const operation of operations) {
            const doc = [operation.documentation.description]
            for (const layer of operation.documentation.layers) {
                if (layer.text !== operation.documentation.description) {
                    doc.push(`@${layer.role === 'original' ? 'source' : layer.role}Description ${layer.text}`)
                }
            }
            doc.push(`@mcpTool ${operation.toolName}`, `@requiredScopes ${operation.requiredScopes.join(', ')}`)
            operation.methodDoc = jsdoc(doc.join('\n\n'))
            if (!categories.has(operation.namespace)) {
                categories.set(operation.namespace, [])
            }
            categories.get(operation.namespace).push(operation)
            records.push({
                domain: operation.namespace,
                method: `${operation.namespace}.${operation.method}`,
                toolName: operation.toolName,
                title: operation.title,
                purpose: operation.selectionHint || operation.title,
                input: `${operation.prefix}Input`,
                output: `${operation.prefix}Output`,
                requiredScopes: operation.requiredScopes,
                ...operation.annotations,
                availability: operation.availability ?? [],
            })
        }
        const clientProperties = []
        const clientFactories = []
        const clientLoaders = []
        const clientInterfaces = []
        const clientTypes = []
        for (const [namespace, members] of categories) {
            const directory = kebabCase(namespace)
            const typeName = `${namespace[0].toUpperCase()}${namespace.slice(1)}Client`
            const imports = [...new Set([typeName, ...members.map((item) => `${item.prefix}Output`)])]
            const signatures = members
                .map(
                    (item) =>
                        `${item.methodDoc}\n${item.method}(input: ${item.prefix}Input, options?: RequestOptions): Promise<${item.prefix}Output>`
                )
                .join('\n')
            clientInterfaces.push(`export interface ${typeName} {\n${signatures}\n}`)
            clientTypes.push(typeName)
            const methods = members
                .map((item) =>
                    item.definition.sharedTool
                        ? `${item.method}: (input, options) => runtime.executeTool<${item.prefix}Output>(${JSON.stringify(item.toolName)}, input, options)`
                        : `${item.method}: (input, options) => runtime.execute<${item.prefix}Output>(${item.method}Definition, input, options)`
                )
                .join(',\n')
            const definitions = members
                .filter((item) => !item.definition.sharedTool)
                .map(
                    (item) =>
                        `const ${item.method}Definition: OperationDefinition = ${JSON.stringify(item.definition)}\n`
                )
                .join('\n')
            await fs.mkdir(path.join(generated, directory), { recursive: true })
            await fs.writeFile(
                path.join(generated, directory, 'client.ts'),
                `${banner}import type { ${imports.join(', ')} } from '../api.js'\nimport type { Runtime } from '../../runtime/client.js'\nimport type { OperationDefinition } from '../../runtime/operation.js'\n${definitions}\nexport function create${typeName}(runtime: Runtime): ${typeName} { return {\n${methods}\n} }\n`
            )
            const exportedNames = names.filter((name) => members.some((item) => name.startsWith(item.prefix)))
            await fs.writeFile(
                path.join(generated, directory, 'index.ts'),
                `${banner}export type { ${[typeName, ...exportedNames].join(', ')} } from '../api.js'\n`
            )
            clientProperties.push(`readonly ${namespace}: ${typeName}`)
            clientLoaders.push(
                `const ${namespace} = new LazyClient<${typeName}>(\n() => import('./${directory}/client.js').then(({ create${typeName} }) => create${typeName}(runtime)),\n(load) => ({\n${members.map((item) => `${item.method}: (input, options) => runtime.runWithDeadline(options, async (signal) => (await load()).${item.method}(input, { ...options, signal }))`).join(',\n')}\n}))`
            )
            clientFactories.push(`get ${namespace}(): ${typeName} { return ${namespace}.client }`)
        }
        await fs.writeFile(
            path.join(generated, 'api.ts'),
            `${banner}import type { JsonObject, JsonValue, ResponseMeta, RequestOptions } from '../types.js'\nexport type { JsonObject, JsonValue, ResponseMeta, RequestOptions } from '../types.js'\nexport interface GeneratedClient {\n${clientProperties.join('\n')}\n}\n${clientInterfaces.join('\n')}\n${source}\n`
        )
        await fs.writeFile(
            path.join(generated, 'client.ts'),
            `${banner}import type { GeneratedClient, ${clientTypes.join(', ')} } from './api.js'\nexport type { GeneratedClient } from './api.js'\nimport type { Runtime } from '../runtime/client.js'\nimport { LazyClient } from '../runtime/lazy-client.js'\nexport function createNamespaces(runtime: Runtime): GeneratedClient {\n${clientLoaders.join('\n')}\nreturn { ${clientFactories.join(', ')} } }\n`
        )
        await fs.writeFile(path.join(generated, 'index.ts'), `${banner}export type * from './api.js'\n`)
        const domains = [...categories].map(([domain, members]) => ({
            domain,
            methods: members.length,
            importPath: `@posthog/sdk/${kebabCase(domain)}`,
        }))
        await fs.writeFile(
            path.join(outputDir, 'api-index.tsv'),
            tsv(
                [
                    'domain',
                    'method',
                    'toolName',
                    'purpose',
                    'input',
                    'output',
                    'requiredScopes',
                    'availability',
                    'readOnly',
                    'destructive',
                    'idempotent',
                ],
                records.map((record) => ({
                    ...record,
                    requiredScopes: record.requiredScopes.join(','),
                    availability: record.availability.join(','),
                }))
            )
        )
        await fs.writeFile(path.join(outputDir, 'domains.tsv'), tsv(['domain', 'methods', 'importPath'], domains))
        await fs.writeFile(path.join(outputDir, 'coverage.json'), JSON.stringify(manifest.coverage, null, 2) + '\n')
        await fs.writeFile(
            path.join(generated, 'discovery.ts'),
            `${banner}import type { OperationInfo, ToolDomain } from '../discovery-types.js'\nexport const operations: readonly OperationInfo[] = ${JSON.stringify(records)}\nexport const domains: readonly ToolDomain[] = ${JSON.stringify(domains)}\n`
        )
        for (const file of await fs.readdir(outputDir, { recursive: true })) {
            if (!/\.(ts|json)$/.test(file)) {
                continue
            }
            const absolute = path.join(outputDir, file)
            const result = await format(file, await fs.readFile(absolute, 'utf8'), formatOptions)
            if (result.errors.length) {
                throw new Error(`Formatting ${file}: ${result.errors.map((error) => error.message).join('; ')}`)
            }
            await fs.writeFile(absolute, result.code)
        }
    } finally {
        await fs.rm(temporary, { recursive: true, force: true })
    }
}
