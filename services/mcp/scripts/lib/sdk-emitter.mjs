import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { format } from 'oxfmt'
import ts from 'typescript'

import { runOrvalParallel } from '../../../../tools/openapi-codegen/src/orval.mjs'

const banner = '// Generated by hogli build:openapi-sdk. Edit the OpenAPI schema or MCP YAML instead.\n'

export function kebabCase(value) {
    return value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
}

function jsdoc(text) {
    return `/**\n${text
        .replace(/\*\//g, '* /')
        .split('\n')
        .map((line) => ` * ${line}`)
        .join('\n')}\n */`
}

function modelDescriptions(value) {
    if (!value || typeof value !== 'object') {
        return
    }
    // Permit additive API fields at runtime without inventing a public index signature for a known object.
    if (value.additionalProperties !== false && Object.keys(value.properties ?? {}).length) {
        delete value.additionalProperties
    }
    if (typeof value['x-source-description'] === 'string') {
        value.description = `${value.description}\n\n@sourceDescription ${value['x-source-description']}`
    }
    if (typeof value.description === 'string') {
        value.description = value.description.replace(/\*\//g, '* /')
    }
    for (const child of Object.values(value)) {
        modelDescriptions(child)
    }
}

function explicitInterfaces(source) {
    const parsed = ts.createSourceFile('models.ts', source, ts.ScriptTarget.Latest, true)
    const replacements = []
    const names = []
    for (const statement of parsed.statements) {
        if (!statement.name) {
            continue
        }
        const name = statement.name.text
        if (name.startsWith('JsonValue') || name === 'JsonObject' || name === 'ResponseMeta') {
            replacements.push({ start: statement.getFullStart(), end: statement.end, value: '' })
            continue
        }
        names.push(name)
        let variant = 0
        const interfaces = []
        const rewrite = (container, skipRoot = false) => {
            const edits = []
            const visit = (node) => {
                if (ts.isTypeLiteralNode(node) && !(skipRoot && node === container)) {
                    const nestedName = `${name}Variant${++variant}`
                    const declaration = rewrite(node, true)
                    interfaces.push(`export interface ${nestedName} ${declaration}`)
                    names.push(nestedName)
                    edits.push({
                        start: node.getStart(parsed) - container.getStart(parsed),
                        end: node.end - container.getStart(parsed),
                        value: nestedName,
                    })
                    return
                }
                ts.forEachChild(node, visit)
            }
            visit(container)
            let text = container.getText(parsed)
            for (const { start, end, value } of edits.sort((a, b) => b.start - a.start)) {
                text = text.slice(0, start) + value + text.slice(end)
            }
            return text
        }
        if (ts.isTypeAliasDeclaration(statement) && ts.isTypeLiteralNode(statement.type)) {
            replacements.push({
                start: statement.getStart(),
                end: statement.end,
                value: `export interface ${name} ${rewrite(statement.type, true)}\n${interfaces.join('\n')}`,
            })
        } else {
            const value = rewrite(statement)
            if (interfaces.length) {
                replacements.push({
                    start: statement.getStart(),
                    end: statement.end,
                    value: `${value}\n${interfaces.join('\n')}`,
                })
            }
        }
    }
    for (const { start, end, value } of replacements.sort((a, b) => b.start - a.start)) {
        source = source.slice(0, start) + value + source.slice(end)
    }
    // Unconstrained JSON leaves have a concrete recursive contract, even when Orval emits unknown.
    const typed = ts.createSourceFile('models.ts', source, ts.ScriptTarget.Latest, true)
    const unknowns = []
    const visit = (node) => {
        if (node.kind === ts.SyntaxKind.UnknownKeyword) {
            unknowns.push({ start: node.getStart(typed), end: node.end })
        }
        ts.forEachChild(node, visit)
    }
    visit(typed)
    for (const { start, end } of unknowns.sort((a, b) => b.start - a.start)) {
        source = source.slice(0, start) + 'JsonValue' + source.slice(end)
    }
    return { source, names: [...new Set(names)] }
}

function typeDocs(schemas) {
    const docs = []
    const visit = (typeName, schema, field) => {
        if (!schema || typeof schema !== 'object') {
            return
        }
        if (schema.description) {
            const original = schema['x-source-description'] ?? schema.description
            const layers = []
            if (!schema['x-override-source'] || schema['x-source-description']) {
                layers.push({
                    role: schema['x-documentation-source'] ? 'original' : 'generated',
                    text: original,
                    source: schema['x-documentation-source'] ?? {
                        kind: 'adapter',
                        file: 'services/mcp/scripts/lib/sdk-schema.mjs',
                    },
                })
            }
            if (schema['x-override-source']) {
                layers.push({ role: 'override', text: schema.description, source: schema['x-override-source'] })
            }
            docs.push({ typeName, ...(field ? { field } : {}), effectiveDescription: schema.description, layers })
        }
        for (const [name, value] of Object.entries(schema.properties ?? {})) {
            visit(typeName, value, field ? `${field}.${name}` : name)
        }
        if (schema.items) {
            visit(typeName, schema.items, `${field ?? ''}[]`)
        }
    }
    for (const [name, schema] of Object.entries(schemas)) {
        visit(name, schema)
    }
    return docs
}

export async function emitSdk(operations, outputDir, manifest) {
    const { $schema, overrides, ignorePatterns, ...formatOptions } = JSON.parse(
        await fs.readFile(new URL('../../../../.oxfmtrc.json', import.meta.url), 'utf8')
    )
    const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'posthog-sdk-'))
    try {
        const jobs = []
        for (const operation of operations) {
            const schemas = structuredClone(operation.registry.schemas)
            modelDescriptions(schemas)
            const input = path.join(temporary, `${operation.prefix}.json`)
            await fs.writeFile(
                input,
                JSON.stringify({
                    openapi: '3.1.0',
                    info: { title: operation.prefix, version: '1' },
                    paths: {},
                    components: { schemas },
                })
            )
            jobs.push({
                label: operation.prefix,
                config: {
                    input,
                    output: {
                        target: path.join(temporary, `${operation.prefix}.ts`),
                        mode: 'split',
                        client: 'fetch',
                        prettier: false,
                        override: {
                            header: () => [],
                            enumGenerationType: 'union',
                            fetch: { includeHttpResponseReturnType: false },
                        },
                    },
                },
            })
        }
        const results = await runOrvalParallel(jobs, { concurrency: 4 })
        for (const result of results) {
            if (result.status === 'rejected') {
                throw result.reason
            }
        }
        const generated = path.join(outputDir, 'src/generated')
        await fs.mkdir(generated, { recursive: true })
        const categories = new Map()
        const records = []
        for (const operation of operations) {
            const directory = kebabCase(operation.namespace)
            const stem = kebabCase(operation.method)
            const modelFile = `src/generated/${directory}/${stem}.ts`
            const raw = await fs.readFile(path.join(temporary, `${operation.prefix}.schemas.ts`), 'utf8')
            const { source, names } = explicitInterfaces(raw)
            const folder = path.join(generated, directory)
            await fs.mkdir(folder, { recursive: true })
            await fs.writeFile(
                path.join(outputDir, modelFile),
                `${banner}import type { JsonObject, JsonValue, ResponseMeta } from '../../types.js'\n${source}\n`
            )
            const doc = [operation.documentation.description]
            for (const layer of operation.documentation.layers) {
                if (layer.text !== operation.documentation.description) {
                    doc.push(`@${layer.role === 'original' ? 'source' : layer.role}Description ${layer.text}`)
                }
            }
            doc.push(`@mcpTool ${operation.toolName}`, `@requiredScopes ${operation.requiredScopes.join(', ')}`)
            const docComment = jsdoc(doc.join('\n\n'))
            operation.methodDoc = docComment
            operation.modelFile = modelFile
            operation.names = names
            if (!categories.has(operation.namespace)) {
                categories.set(operation.namespace, [])
            }
            categories.get(operation.namespace).push(operation)
            const reference = (name) => ({
                name,
                importPath: `@posthog/sdk/${directory}`,
                source: modelFile,
                declaration: `dist/generated/${directory}/${stem}.d.ts`,
            })
            const input = reference(`${operation.prefix}Input`)
            const output = reference(`${operation.prefix}Output`)
            const method = `${operation.namespace}.${operation.method}`
            records.push({
                method,
                toolName: operation.toolName,
                operationId: operation.operationId,
                title: operation.title,
                category: operation.category,
                description: operation.documentation.description,
                ...(operation.selectionHint ? { selectionHint: operation.selectionHint } : {}),
                requiredScopes: operation.requiredScopes,
                annotations: operation.annotations,
                availability: operation.availability ?? [],
                methodSource: `src/generated/${directory}/client.ts`,
                input,
                output,
                referencedTypes: names.filter((name) => name !== input.name && name !== output.name).map(reference),
                methodDocumentation: operation.documentation.layers,
                typeDocumentation: typeDocs(operation.registry.schemas),
                relatedTools: [],
                descriptionFile: `catalog/${directory}/${stem}.json`,
                types: `${docComment}\n${source}`,
            })
        }
        const toolNames = new Map(manifest.coverage.map((item) => [item.toolName, item]))
        for (const record of records) {
            const referenced = new Set(
                [...record.description.matchAll(/`([a-z][a-z0-9-]+)`/g)]
                    .map((match) => match[1])
                    .filter((name) => toolNames.has(name) && name !== record.toolName)
            )
            record.relatedTools = [...referenced].map((toolName) => {
                const entry = toolNames.get(toolName)
                return { toolName, ...(entry.method ? { method: entry.method } : { unavailableReason: entry.reason }) }
            })
            const { descriptionFile, types, ...publicRecord } = record
            await fs.mkdir(path.dirname(path.join(outputDir, descriptionFile)), { recursive: true })
            await fs.writeFile(path.join(outputDir, descriptionFile), JSON.stringify(publicRecord, null, 2) + '\n')
        }
        const clientImports = []
        const clientProperties = []
        const clientFactories = []
        for (const [namespace, members] of categories) {
            const directory = kebabCase(namespace)
            const typeName = `${namespace[0].toUpperCase()}${namespace.slice(1)}Client`
            const imports = members
                .map(
                    (item) =>
                        `import type { ${item.prefix}Input, ${item.prefix}Output } from './${kebabCase(item.method)}.js'`
                )
                .join('\n')
            const signatures = members
                .map(
                    (item) =>
                        `${item.methodDoc}\n${item.method}(input: ${item.prefix}Input, options?: RequestOptions): Promise<${item.prefix}Output>`
                )
                .join('\n')
            const methods = members
                .map((item) =>
                    item.definition.sharedTool
                        ? `${item.method}: (input, options) => runtime.executeTool<${item.prefix}Output>(${JSON.stringify(item.toolName)}, input, options)`
                        : `${item.method}: (input, options) => runtime.execute<${item.prefix}Output>(${item.method}Definition, input, options)`
                )
                .join(',\n')
            const definitions = members
                .filter((item) => !item.definition.sharedTool)
                .map(
                    (item) =>
                        `const ${item.method}Definition: OperationDefinition = ${JSON.stringify(item.definition)}\n`
                )
                .join('\n')
            await fs.writeFile(
                path.join(generated, directory, 'client.ts'),
                `${banner}import type { RequestOptions } from '../../types.js'\nimport type { Runtime } from '../../runtime/client.js'\nimport type { OperationDefinition } from '../../runtime/operation.js'\n${imports}\n${definitions}\nexport interface ${typeName} {\n${signatures}\n}\nexport function create${typeName}(runtime: Runtime): ${typeName} { return {\n${methods}\n} }\n`
            )
            await fs.writeFile(
                path.join(generated, directory, 'index.ts'),
                `${banner}${members.map((item) => `export type { ${item.names.join(', ')} } from './${kebabCase(item.method)}.js'`).join('\n')}\nexport type { ${typeName} } from './client.js'\n`
            )
            clientImports.push(`import { create${typeName}, type ${typeName} } from './${directory}/client.js'`)
            clientProperties.push(`readonly ${namespace}: ${typeName}`)
            clientFactories.push(`${namespace}: create${typeName}(runtime)`)
        }
        await fs.writeFile(
            path.join(generated, 'client.ts'),
            `${banner}import type { Runtime } from '../runtime/client.js'\n${clientImports.join('\n')}\nexport interface GeneratedClient {\n${clientProperties.join('\n')}\n}\nexport function createNamespaces(runtime: Runtime): GeneratedClient { return { ${clientFactories.join(', ')} } }\n`
        )
        await fs.writeFile(
            path.join(generated, 'index.ts'),
            `${banner}${[...categories.keys()].map((namespace) => `export type * from './${kebabCase(namespace)}/index.js'`).join('\n')}\n`
        )
        const catalog = {
            schemaVersion: 1,
            packageVersion: manifest.packageVersion,
            sourceRevision: manifest.sourceRevision,
            schemaHash: manifest.schemaHash,
            tools: records.map((item) => ({
                method: item.method,
                toolName: item.toolName,
                title: item.title,
                ...(item.selectionHint ? { selectionHint: item.selectionHint } : {}),
                descriptionFile: item.descriptionFile,
            })),
        }
        await fs.writeFile(path.join(outputDir, 'catalog.json'), JSON.stringify(catalog, null, 2) + '\n')
        await fs.writeFile(path.join(outputDir, 'coverage.json'), JSON.stringify(manifest.coverage, null, 2) + '\n')
        await fs.writeFile(
            path.join(generated, 'discovery.ts'),
            `${banner}import type { ToolCatalog, ToolSearchResult } from '../discovery-types.js'\nexport const catalog: ToolCatalog = ${JSON.stringify(catalog)}\nexport const descriptions: (ToolSearchResult & { description: string })[] = ${JSON.stringify(records.map(({ method, toolName, title, selectionHint, descriptionFile, description }) => ({ method, toolName, title, selectionHint, descriptionFile, description })))}\n`
        )
        for (const file of await fs.readdir(outputDir, { recursive: true })) {
            if (!/\.(ts|json)$/.test(file)) {
                continue
            }
            const absolute = path.join(outputDir, file)
            const result = await format(file, await fs.readFile(absolute, 'utf8'), formatOptions)
            if (result.errors.length) {
                throw new Error(`Formatting ${file}: ${result.errors.map((error) => error.message).join('; ')}`)
            }
            await fs.writeFile(absolute, result.code)
        }
    } finally {
        await fs.rm(temporary, { recursive: true, force: true })
    }
}
