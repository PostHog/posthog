// `sceneLogic` asks the chunk loader for `ESBUILD_LOAD_CHUNKS(sceneId)` before it imports a scene,
// so the browser can fetch every chunk of the scene in parallel instead of discovering them level
// by level. The generated imports and this chunk map use the same scene manifest.

const SCENES_INPUT = 'src/lazySceneImports.ts'
const INDEX_ENTRY = 'src/index.tsx'

/** @param {[string, string][]} entries */
export function createSceneManifest(entries) {
    /** @type {Record<string, string>} */
    const manifest = {}
    for (const [id, specifier] of entries) {
        if (Object.hasOwn(manifest, id)) {
            throw new Error(`Duplicate scene ${id}`)
        }
        manifest[id] = specifier
    }
    return manifest
}

/** @param {Record<string, string>} sceneModules */
export function sceneImportsSource(sceneModules) {
    const imports = Object.entries(sceneModules).map(
        ([id, specifier]) => `${JSON.stringify(id)}: () => import(${JSON.stringify(specifier)}),`
    )
    return `
        // Generated by build-products.mjs. Edit appSceneModules.mts or the product manifest instead.
        //
        // Kept separate from products.tsx on purpose: this map's dynamic imports reach every
        // product scene, and products.tsx is imported app-wide via scenes/urls.ts. In one module,
        // jest's --findRelatedTests would mark ~the whole test suite as related to any scene change.
        // Import this only from scene-mounting code (scenes/appScenes.ts).

        import type sceneModules from './sceneModules.json'

        export const lazySceneImports = {
            ${imports.join('\n')}
        } satisfies Record<keyof typeof sceneModules, () => Promise<Record<string, unknown>>>
    `
}

function chunkIdsOf(output) {
    return (output.imports || [])
        .filter((i) => i.kind === 'import-statement' && i.path.startsWith('dist/chunk-'))
        .map((i) => i.path.replace('dist/chunk-', '').replace('.js', ''))
}

export function keyChunksBySceneId({ inputs, outputs, sceneModules }) {
    if (Object.keys(sceneModules).length === 0) {
        throw new Error('Chunk map: scene manifest is empty')
    }
    const specifierToModule = new Map(
        (inputs[SCENES_INPUT]?.imports || [])
            .filter((imp) => imp.kind === 'dynamic-import')
            .map((imp) => [imp.original, imp.path])
    )
    const entryOutputByModule = new Map(
        Object.entries(outputs)
            .filter(([outputPath, output]) => output.entryPoint && outputPath.endsWith('.js'))
            .map(([, output]) => [output.entryPoint, output])
    )
    const indexOutput = entryOutputByModule.get(INDEX_ENTRY)
    if (!indexOutput) {
        throw new Error('Chunk map: no JavaScript output for index')
    }
    /** @type {Record<string, string[]>} */
    const chunks = { index: chunkIdsOf(indexOutput) }
    for (const [id, specifier] of Object.entries(sceneModules)) {
        const output = entryOutputByModule.get(specifierToModule.get(specifier))
        if (!output) {
            throw new Error(`Chunk map: no JavaScript output for scene ${id} (${specifier})`)
        }
        chunks[id] = chunkIdsOf(output)
    }
    return chunks
}
