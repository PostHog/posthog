export type actionsModelType = MakeLogicType<
    actionsModelValues,
    actionsModelActions,
    ActionsModelProps,
    actionsModelMeta
>

export const actionsModel = kea<actionsModelType>([
    props({} as ActionsModelProps),
    key((props) => (props.skipLoad ? 'skip-load' : 'default')),
    path((key) => ['models', 'actionsModel', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
        actions: [teamLogic, ['loadCurrentTeamSuccess']],
    })),
    loaders(({ cache, props, values, actions }) => ({
        actions: {
            __default: [] as ActionType[],
            loadActions: async (force: boolean = false, breakpoint) => {
                if (!force && values.actionsLoaded) {
                    return values.actions
                }
                if (!force && cache.actionsRequest) {
                    const actions = await cache.actionsRequest
                    breakpoint()
                    return actions
                }

                const request = api.actions.list(props.params).then((response) => response.results ?? [])
                cache.actionsRequest = request

                try {
                    const actions = await request
                    breakpoint()
                    return actions.map((action) => cache.actionOverrides?.[action.id] ?? action)
                } finally {
                    if (cache.actionsRequest === request) {
                        cache.actionsRequest = null
                    }
                }
            },
            updateAction: (action: ActionType) => (values.actions || []).map((a) => (action.id === a.id ? action : a)),
        },
        pin: {
            pinAction: async (action: ActionType) => {
                const response = await api.actions.update(action.id, {
                    name: action.name,
                    pinned_at: new Date().toISOString(),
                })
                actions.updateAction(response)
            },
            unpinAction: async (action: ActionType) => {
                const response = await api.actions.update(action.id, {
                    name: action.name,
                    pinned_at: null,
                })
                actions.updateAction(response)
            },
        },
    })),
    reducers({
        actions: [
            [] as ActionType[],
            {
                loadCurrentTeamSuccess: (state, { currentTeam }) => (currentTeam ? [] : state),
            },
        ],
        actionsLoaded: [
            false,
            {
                loadActionsSuccess: () => true,
                loadCurrentTeamSuccess: () => false,
            },
        ],
    }),
    selectors(({ selectors }) => ({
        actionsGrouped: [
            () => [selectors.actions],
            (actions: ActionType[]) => {
                return [
                    {
                        label: 'Select an action',
                        options: actions.map((action) => {
                            return { label: action.name, value: action.id }
                        }),
                    },
                ]
            },
        ],
        actionsById: [
            (s) => [s.actions],
            (actions: ActionType[]): Partial<Record<string | number, ActionType>> =>
                Object.fromEntries(actions.map((action) => [action.id, action])),
        ],
        actionsSorted: [
            (s) => [s.actions],
            (actions: ActionType[]): ActionType[] => {
                return actions.sort((a, b) => (b.pinned_at ? 1 : 0) - (a.pinned_at ? 1 : 0))
            },
        ],
    })),
    events(({ props, values, actions }) => ({
        afterMount: () => {
            if (!props.skipLoad && isAuthenticatedTeam(values.currentTeam)) {
                actions.loadActions()
            }
        },
    })),
    permanentlyMount(),
])
