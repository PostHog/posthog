export interface ActionsModelProps {
    params?: string
    skipLoad?: boolean
}

export function findActionName(id: number): string | null {
    for (const logic of actionsModel.findAllMounted()) {
        const action = logic.values.actions.find((candidate) => candidate.id === id)
        if (action?.name) {
            return action.name
        }
    }
    return null
}

export function refreshMountedActions(): void {
    for (const logic of actionsModel.findAllMounted()) {
        logic.actions.loadActions(true)
    }
}

export function updateMountedAction(action: ActionType): void {
    for (const logic of actionsModel.findAllMounted()) {
        logic.cache.actionOverrides = { ...logic.cache.actionOverrides, [action.id]: action }
        logic.actions.updateAction(action)
    }
}

