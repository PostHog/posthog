const POLL_TIMEOUT = 5000

export function getReferencedCohortIds(query: unknown): number[] {
    const ids = new Set<number>()
    const add = (value: unknown): void => {
        for (const candidate of Array.isArray(value) ? value : [value]) {
            if (typeof candidate === 'number' || (typeof candidate === 'string' && /^\d+$/.test(candidate))) {
                const id = Number(candidate)
                if (Number.isSafeInteger(id) && id > 0) {
                    ids.add(id)
                }
            }
        }
    }
    const visit = (value: unknown): void => {
        if (!value || typeof value !== 'object') {
            return
        }
        if (Array.isArray(value)) {
            value.forEach(visit)
            return
        }
        const node = value as Record<string, unknown>
        if (node.type === 'cohort') {
            add(node.value)
        }
        if (node.breakdown_type === 'cohort') {
            add(node.breakdown)
        }
        Object.values(node).forEach(visit)
    }
    visit(query)
    return [...ids]
}

export function isIndividualInsightPath(pathname: string): boolean {
    const match = pathname.match(/^(?:\/project\/[^/]+)?\/insights\/([^/]+)(?:\/[^/]+){0,2}\/?$/)
    return !!match && match[1] !== 'quick-start'
}

export const COHORTS_PER_PAGE = 100

// The cohort list returns at most 1000 rows per request, so a full-list load reads every page.
const COHORTS_FULL_LIST_PAGE_SIZE = 1000

export interface CohortFilters {
    search?: string
    page?: number
}

export const DEFAULT_COHORT_FILTERS: CohortFilters = {
    search: undefined,
    page: 1,
}

async function loadAllCohortPages<T>(
    loadPage: (params: {
        limit: number
        offset: number
    }) => Promise<{ count: number; next?: string | null; results: T[] }>
): Promise<CountedPaginatedResponse<T>> {
    const results: T[] = []
    let count = 0
    let hasNextPage = true
    while (hasNextPage) {
        const page = await loadPage({ limit: COHORTS_FULL_LIST_PAGE_SIZE, offset: results.length })
        results.push(...page.results)
        count = page.count
        hasNextPage = !!page.next && page.results.length > 0
    }
    return { count, results }
}

