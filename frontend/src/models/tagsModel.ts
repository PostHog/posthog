import { MakeLogicType, actions, kea, listeners, path } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import { teamLogic } from 'scenes/teamLogic'

const tagsByProject = new Map<number, string[]>()
const tagsRequests = new Map<number, Promise<string[]>>()

async function loadProjectTags(projectId: number): Promise<string[]> {
    const cachedTags = tagsByProject.get(projectId)
    if (cachedTags) {
        return cachedTags
    }
    const existingRequest = tagsRequests.get(projectId)
    if (existingRequest) {
        return await existingRequest
    }

    const request = api.tags.list().then((tags) => {
        const projectTags = tags || []
        tagsByProject.set(projectId, projectTags)
        return projectTags
    })
    tagsRequests.set(projectId, request)

    try {
        return await request
    } finally {
        if (tagsRequests.get(projectId) === request) {
            tagsRequests.delete(projectId)
        }
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tagsModelValues {
    tags: string[]
    tagsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface tagsModelActions {
    loadTags: () => any
    loadTagsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadTagsIfNeeded: () => {
        value: true
    }
    loadTagsSuccess: (
        tags: string[],
        payload?: any
    ) => {
        tags: string[]
        payload?: any
    }
    refreshTags: () => {
        value: true
    }
}

export type tagsModelType = MakeLogicType<tagsModelValues, tagsModelActions>

export const tagsModel = kea<tagsModelType>([
    path(['models', 'tagsModel']),
    actions({
        loadTagsIfNeeded: true,
        refreshTags: true,
    }),
    loaders(() => ({
        tags: {
            __default: [] as string[],
            loadTags: async () => {
                const projectId = teamLogic.values.currentTeamId
                return projectId === null ? [] : await loadProjectTags(projectId)
            },
        },
    })),
    listeners(({ actions }) => ({
        loadTagsIfNeeded: () => {
            actions.loadTags()
        },
        refreshTags: () => {
            const projectId = teamLogic.values.currentTeamId
            if (projectId === null) {
                return
            }

            tagsByProject.delete(projectId)
            actions.loadTags()
        },
    })),
])
