export type tagsModelType = MakeLogicType<tagsModelValues, tagsModelActions, Record<string, any>, tagsModelMeta>

export const tagsModel = kea<tagsModelType>([
    path(['models', 'tagsModel']),
    actions({
        loadTags: true,
        loadTagsIfNeeded: true,
        loadTagsSuccess: (tags: string[], projectId?: number) => ({ tags, projectId }),
        refreshTags: true,
        setProjectTags: (projectId: number, tags: string[]) => ({ projectId, tags }),
        setProjectTagsLoading: (projectId: number, loading: boolean) => ({ projectId, loading }),
    }),
    reducers({
        tagsByProject: [
            {} as Record<number, string[]>,
            {
                setProjectTags: (state, { projectId, tags }) => ({ ...state, [projectId]: tags }),
            },
        ],
        tagsLoadingByProject: [
            {} as Record<number, boolean>,
            {
                setProjectTagsLoading: (state, { projectId, loading }) => ({ ...state, [projectId]: loading }),
            },
        ],
    }),
    selectors({
        tags: [
            (s) => [s.tagsByProject, s.tagsLoadingByProject],
            (tagsByProject: Record<number, string[]>): string[] => {
                const projectId = teamLogic.values.currentTeamId
                return projectId === null ? [] : (tagsByProject[projectId] ?? [])
            },
        ],
        tagsLoading: [
            (s) => [s.tagsLoadingByProject],
            (tagsLoadingByProject: Record<number, boolean>): boolean => {
                const projectId = teamLogic.values.currentTeamId
                return projectId === null ? false : (tagsLoadingByProject[projectId] ?? false)
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        loadTags: async () => {
            const projectId = teamLogic.values.currentTeamId
            if (projectId === null) {
                return
            }

            actions.setProjectTagsLoading(projectId, true)
            try {
                actions.loadTagsSuccess(await fetchProjectTags(projectId), projectId)
            } finally {
                actions.setProjectTagsLoading(projectId, false)
            }
        },
        loadTagsIfNeeded: () => {
            const projectId = teamLogic.values.currentTeamId
            if (projectId === null || values.tagsByProject[projectId]) {
                return
            }

            actions.loadTags()
        },
        loadTagsSuccess: ({ tags, projectId }) => {
            const resolvedProjectId = projectId ?? teamLogic.values.currentTeamId
            if (resolvedProjectId !== null) {
                actions.setProjectTags(resolvedProjectId, tags)
            }
        },
        refreshTags: () => {
            const projectId = teamLogic.values.currentTeamId
            if (projectId === null) {
                return
            }

            actions.setProjectTagsLoading(projectId, false)
            actions.setProjectTags(projectId, [])
            actions.loadTags()
        },
    })),
])
