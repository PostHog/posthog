export type groupsModelType = MakeLogicType<groupsModelValues, groupsModelActions, Record<string, any>, groupsModelMeta>

export const groupsModel = kea<groupsModelType>([
    path(['models', 'groupsModel']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], groupsAccessLogic, ['groupsEnabled', 'groupsAccessStatus']],
        actions: [userLogic, ['loadUserSuccess', 'updateUserSuccess']],
    })),
    loaders(({ values }) => ({
        groupTypesRaw: [
            [] as Array<GroupType>,
            {
                loadAllGroupTypes: async () => {
                    if (!values.currentProjectId) {
                        return []
                    }
                    const groupTypes = await groupsTypesList(String(values.currentProjectId))
                    return groupTypes.map(toGroupType)
                },
                updateGroupTypesMetadata: async (payload: Array<GroupType>) => {
                    if (values.groupsEnabled) {
                        const groupTypes = await groupsTypesUpdateMetadataPartialUpdate(
                            String(values.currentProjectId),
                            payload.map(({ group_type_index, name_singular, name_plural }) => ({
                                group_type_index,
                                name_singular,
                                name_plural,
                            }))
                        )
                        return groupTypes.map(toGroupType)
                    }
                    return []
                },
                deleteGroupType: async (groupTypeIndex: number) => {
                    if (values.groupsEnabled) {
                        await groupsTypesDestroy(String(values.currentProjectId), groupTypeIndex)
                    }
                    return []
                },
                createDetailDashboard: async (groupTypeIndex: number) => {
                    const groupType = toGroupType(
                        await groupsTypesCreateDetailDashboardUpdate(String(values.currentProjectId), {
                            group_type_index: groupTypeIndex,
                        })
                    )
                    return values.groupTypesRaw.map((gt) => (gt.group_type_index === groupTypeIndex ? groupType : gt))
                },
                removeDetailDashboard: async (dashboardId: number) => {
                    return values.groupTypesRaw.map((gt) => {
                        if (gt.detail_dashboard === dashboardId) {
                            return {
                                ...gt,
                                detail_dashboard: null,
                            }
                        }
                        return gt
                    })
                },
                setDefaultColumns: async ({
                    groupTypeIndex,
                    defaultColumns,
                }: {
                    groupTypeIndex: number
                    defaultColumns: string[]
                }) => {
                    const groupType = toGroupType(
                        await groupsTypesSetDefaultColumnsUpdate(String(values.currentProjectId), {
                            group_type_index: groupTypeIndex,
                            default_columns: defaultColumns,
                        })
                    )
                    return values.groupTypesRaw.map((gt) => (gt.group_type_index === groupTypeIndex ? groupType : gt))
                },
            },
        ],
    })),
    selectors({
        groupTypes: [
            (s) => [s.groupTypesRaw],
            (groupTypesRaw: Array<GroupType>) =>
                new Map<GroupTypeIndex, GroupType>(
                    (groupTypesRaw ?? []).map((groupType) => [groupType.group_type_index, groupType])
                ),
        ],
        groupTypesLoading: [(s) => [s.groupTypesRawLoading], (groupTypesRawLoading: boolean) => groupTypesRawLoading],

        showGroupsOptions: [
            (s) => [s.groupsAccessStatus, s.groupsEnabled, s.groupTypes],
            (status: GroupsAccessStatus, enabled: boolean, groupTypes: Map<GroupTypeIndex, GroupType>) =>
                status !== GroupsAccessStatus.Hidden || (enabled && Array.from(groupTypes.values()).length > 0),
        ],
        groupsTaxonomicTypes: [
            (s) => [s.groupTypes],
            (groupTypes: Map<GroupTypeIndex, GroupType>): TaxonomicFilterGroupType[] => {
                return Array.from(groupTypes.values()).map(
                    (groupType: GroupType) =>
                        `${TaxonomicFilterGroupType.GroupsPrefix}_${groupType.group_type_index}` as TaxonomicFilterGroupType
                )
            },
        ],
        groupNamesTaxonomicTypes: [
            (s) => [s.groupTypes],
            (groupTypes: Map<GroupTypeIndex, GroupType>): TaxonomicFilterGroupType[] => {
                return Array.from(groupTypes.values()).map(
                    (groupType: GroupType) =>
                        `${TaxonomicFilterGroupType.GroupNamesPrefix}_${groupType.group_type_index}` as TaxonomicFilterGroupType
                )
            },
        ],
        aggregationLabel: [
            (s) => [s.groupTypes],
            (groupTypes: Map<GroupTypeIndex, GroupType>) =>
                (groupTypeIndex: number | null | undefined, deferToUserWording: boolean = false): Noun => {
                    if (groupTypeIndex != undefined) {
                        const groupType = groupTypes.get(groupTypeIndex as GroupTypeIndex)
                        if (groupType) {
                            return {
                                singular: groupType.name_singular || groupType.group_type || 'group',
                                plural: groupType.name_plural || wordPluralize(groupType.group_type) || 'groups',
                            }
                        }
                        return {
                            singular: 'unknown group',
                            plural: 'unknown groups',
                        }
                    }
                    return deferToUserWording
                        ? {
                              singular: 'user',
                              plural: 'users',
                          }
                        : { singular: 'person', plural: 'persons' }
                },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        // groupsEnabled comes from the organization's available features on the user, so it can only
        // turn on when the user reloads, for example after an upgrade.
        const loadGroupTypesIfGroupsTurnedOn = (): void => {
            if (values.groupsEnabled && !cache.groupsWereEnabled && !values.groupTypesLoading) {
                actions.loadAllGroupTypes()
            }
            cache.groupsWereEnabled = values.groupsEnabled
        }
        return {
            loadUserSuccess: loadGroupTypesIfGroupsTurnedOn,
            updateUserSuccess: loadGroupTypesIfGroupsTurnedOn,
            deleteGroupTypeSuccess: () => {
                actions.loadAllGroupTypes()
            },
        }
    }),
    afterMount(({ actions, values, cache }) => {
        cache.groupsWereEnabled = values.groupsEnabled
        if (window.POSTHOG_APP_CONTEXT?.current_team?.group_types) {
            actions.loadAllGroupTypesSuccess(window.POSTHOG_APP_CONTEXT.current_team.group_types)
        } else {
            actions.loadAllGroupTypes()
        }
    }),
])
