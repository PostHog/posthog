import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import posthog from 'posthog-js'

import { navigateToHref } from 'lib/utils/navigateToHref'

import { recentItemsModel } from '~/models/recentItemsModel'
import { FileSystemEntry } from '~/queries/schema/schema-general'

import { TodayMonitorRecent } from './todayMonitor'
import { TodayPeopleRecent } from './todayPeople'
import { StoredReleaseRecent, TodayViewedRecent } from './todayRecents'
import { todayRecentsLogic } from './todayRecentsLogic'
import { TodayRecentsMenuItem, todayRecentsMenuItems } from './todayRecentsMenu'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentsMenuLogicValues {
    recents: FileSystemEntry[] // recentItemsModel
    recentsHasLoaded: boolean // recentItemsModel
    monitorRecents: TodayViewedRecent<TodayMonitorRecent>[] // todayRecentsLogic
    peopleRecents: TodayViewedRecent<TodayPeopleRecent>[] // todayRecentsLogic
    releaseRecents: StoredReleaseRecent[] // todayRecentsLogic
    menuItems: TodayRecentsMenuItem[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentsMenuLogicActions {
    loadRecents: () => any // recentItemsModel
    menuOpened: () => {
        value: true
    }
    recentOpened: (
        item: TodayRecentsMenuItem,
        position: number
    ) => {
        item: TodayRecentsMenuItem
        position: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentsMenuLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        menuItems: (
            recents: FileSystemEntry[],
            peopleRecents: TodayViewedRecent<TodayPeopleRecent>[],
            monitorRecents: TodayViewedRecent<TodayMonitorRecent>[],
            releaseRecents: StoredReleaseRecent[]
        ) => TodayRecentsMenuItem[]
    }
}

export type todayRecentsMenuLogicType = MakeLogicType<
    todayRecentsMenuLogicValues,
    todayRecentsMenuLogicActions,
    Record<string, any>,
    todayRecentsMenuLogicMeta
>

/** The top bar's Recents menu: everything a person opened, from every rail pane, in one list. */
export const todayRecentsMenuLogic = kea<todayRecentsMenuLogicType>([
    path(['layout', 'today', 'todayRecentsMenuLogic']),
    connect(() => ({
        values: [
            todayRecentsLogic,
            ['monitorRecents', 'peopleRecents', 'releaseRecents'],
            recentItemsModel,
            ['recents', 'recentsHasLoaded'],
        ],
        actions: [recentItemsModel, ['loadRecents']],
    })),
    actions({
        menuOpened: true,
        recentOpened: (item: TodayRecentsMenuItem, position: number) => ({ item, position }),
    }),
    selectors({
        menuItems: [
            (s) => [s.recents, s.peopleRecents, s.monitorRecents, s.releaseRecents],
            (
                recents: FileSystemEntry[],
                peopleRecents: TodayViewedRecent<TodayPeopleRecent>[],
                monitorRecents: TodayViewedRecent<TodayMonitorRecent>[],
                releaseRecents: StoredReleaseRecent[]
            ): TodayRecentsMenuItem[] =>
                todayRecentsMenuItems(recents, [...peopleRecents, ...monitorRecents, ...releaseRecents]),
        ],
    }),
    listeners(({ actions, values }) => ({
        menuOpened: () => {
            // The file system list loads once per project, so a page opened since then would be missing.
            actions.loadRecents()
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('today recents menu opened', { recent_count: values.menuItems.length })
        },
        recentOpened: ({ item, position }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('today recents menu item opened', {
                object_type: item.type,
                position,
                recent_count: values.menuItems.length,
            })
            navigateToHref(item.href)
        },
    })),
])
