export const todayRailStatusLogic = kea<todayRailStatusLogicType>([
    path(['layout', 'today', 'todayRailStatusLogic']),
    connect(() => ({
        values: [
            posthogStatusLogic,
            ['postHogStatusTooltip', 'postHogStatusBadgeStatus'],
            helpMenuLogic,
            ['triggerBadgeStatus'],
            healthSummaryLogic,
            ['healthSummary', 'unsnoozedCount', 'snoozedCount'],
            preflightLogic,
            ['preflight'],
            billingLogic,
            ['effectiveBillingAlert'],
            pendingInvitesLogic,
            ['pendingInvitesLabel'],
        ],
    })),
    selectors({
        statusSeverity: [
            (s) => [s.postHogStatusBadgeStatus],
            (status: PostHogStatusBadgeStatus): TodayRailSeverity => severityFromBadgeStatus(status),
        ],
        statusText: [
            (s) => [s.postHogStatusTooltip, s.preflight],
            // Local dev never loads the status page summary, so it has no text to show.
            (tooltip: string | null, preflight: PreflightStatus | null): string | null =>
                tooltip ?? (preflight?.is_debug ? 'All systems operational' : null),
        ],
        healthSeverity: [
            (s) => [s.triggerBadgeStatus],
            (status: HelpBadgeStatus): TodayRailSeverity => severityFromBadgeStatus(status),
        ],
        healthText: [
            (s) => [s.healthSummary, s.unsnoozedCount, s.snoozedCount],
            (healthSummary: HealthIssueSummary | null, unsnoozedCount: number, snoozedCount: number): string | null =>
                healthSummary ? healthSummaryLabel(unsnoozedCount, snoozedCount) : null,
        ],
        moreSeverity: [
            (s) => [s.statusSeverity, s.healthSeverity],
            (statusSeverity: TodayRailSeverity, healthSeverity: TodayRailSeverity): TodayRailSeverity =>
                worstSeverity(statusSeverity, healthSeverity),
        ],
        moreLabel: [
            (s) => [s.statusSeverity, s.statusText, s.healthSeverity, s.healthText],
            (
                statusSeverity: TodayRailSeverity,
                statusText: string | null,
                healthSeverity: TodayRailSeverity,
                healthText: string | null
            ): string =>
                ['More', statusSeverity !== 'ok' && statusText, healthSeverity !== 'ok' && healthText]
                    .filter(Boolean)
                    .join(', '),
        ],
        billingSeverity: [
            (s) => [s.effectiveBillingAlert],
            (alert: BillingAlertConfig | null): TodayRailSeverity => severityFromBillingAlert(alert),
        ],
        billingText: [
            (s) => [s.effectiveBillingAlert],
            (alert: BillingAlertConfig | null): string | null => alert?.title ?? null,
        ],
        orgSeverity: [
            (s) => [s.billingSeverity, s.pendingInvitesLabel],
            (billingSeverity: TodayRailSeverity, pendingInvitesLabel: string | null): TodayRailSeverity =>
                worstSeverity(billingSeverity, pendingInvitesLabel ? 'notice' : 'none'),
        ],
        orgProblems: [
            (s) => [s.billingSeverity, s.billingText, s.pendingInvitesLabel],
            (
                billingSeverity: TodayRailSeverity,
                billingText: string | null,
                pendingInvitesLabel: string | null
            ): string[] =>
                [billingSeverity !== 'none' && billingText, pendingInvitesLabel].filter(
                    (problem): problem is string => !!problem
                ),
        ],
    }),
])
