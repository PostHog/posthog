/** The Views pane's recently viewed list: dashboards and notebooks from the project's recents, and canvases. */
export const todayRecentViewsLogic = kea<todayRecentViewsLogicType>([
    path(['layout', 'today', 'todayRecentViewsLogic']),
    connect(() => ({
        values: [recentItemsModel, ['recents'], teamLogic, ['currentTeamId']],
        actions: [recentItemsModel, ['recordView', 'viewLogged']],
    })),
    loaders(({ values }) => ({
        // Canvases are not file system entries, so their views come from the view log instead of the recents fetch.
        recentCanvases: [
            [] as TodayRecentEntry[],
            {
                loadRecentCanvases: async (_: void, breakpoint) => {
                    const projectId = values.currentTeamId ? String(values.currentTeamId) : null
                    if (!projectId) {
                        return []
                    }
                    const views = await api.fileSystemLogView.list({ type: 'canvas', limit: TODAY_RECENTS_LIMIT })
                    const results = await Promise.allSettled(
                        views.map(async ({ ref, viewed_at }): Promise<TodayRecentEntry> => {
                            const canvas = await canvasesRetrieve(projectId, ref)
                            return {
                                key: `canvas-${canvas.id}`,
                                type: 'canvas',
                                name: canvas.name || 'Untitled canvas',
                                href: urls.canvasDetail(canvas.id),
                                viewedAt: viewed_at,
                            }
                        })
                    )
                    breakpoint()
                    // A deleted canvas fails its lookup, so it drops out of the list.
                    return results.flatMap((result) => (result.status === 'fulfilled' ? [result.value] : []))
                },
            },
        ],
    })),
    reducers({
        recentCanvases: {
            recordView: (state, { type, ref }) =>
                type === 'canvas'
                    ? state.map((recent) =>
                          recent.key === `canvas-${ref}` ? { ...recent, viewedAt: new Date().toISOString() } : recent
                      )
                    : state,
        },
    }),
    selectors({
        recentViewEntries: [
            (s) => [s.recents, s.recentCanvases],
            (recents: FileSystemEntry[], recentCanvases: TodayRecentEntry[]): TodayRecentEntry[] =>
                newestByName(
                    [...recents.flatMap((entry) => fileSystemRecentEntry(entry) ?? []), ...recentCanvases].sort(
                        (first, second) => second.viewedAt.localeCompare(first.viewedAt)
                    ),
                    (recent) => recent.name,
                    (recent) => recent.key,
                    TODAY_RECENTS_LIMIT
                ),
        ],
    }),
    listeners(({ actions }) => ({
        viewLogged: ({ type }) => {
            if (type === 'canvas') {
                actions.loadRecentCanvases()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRecentCanvases()
    }),
])
