/** The Views pane's recently viewed list: dashboards and notebooks from the project's recents, and canvases. */
export const todayRecentViewsLogic = kea<todayRecentViewsLogicType>([
    path(['layout', 'today', 'todayRecentViewsLogic']),
    connect(() => ({
        values: [recentItemsModel, ['recents'], teamLogic, ['currentTeamId']],
        actions: [recentItemsModel, ['recordView', 'viewLogged'], teamLogic, ['loadCurrentTeamSuccess']],
    })),
    loaders(({ values }) => ({
        // Canvases are not file system entries, so their views come from the view log instead of the recents fetch.
        recentCanvases: [
            [] as TodayRecentEntry[],
            {
                loadRecentCanvases: async (_: void, breakpoint) => {
                    const projectId = values.currentTeamId ? String(values.currentTeamId) : null
                    if (!projectId) {
                        return []
                    }
                    // Deleted canvases keep their view logs, so scan past them to still fill the list.
                    const views = await withTimeout(
                        (signal) =>
                            api.fileSystemLogView.list({ type: 'canvas', limit: CANVAS_VIEW_SCAN_LIMIT, signal }),
                        CANVAS_LOOKUP_TIMEOUT_MS
                    )
                    const results = await Promise.allSettled(
                        views.map(async ({ ref, viewed_at }): Promise<TodayRecentEntry> => {
                            // A stalled lookup must not hold back the canvases that did load.
                            const canvas = await withTimeout(
                                (signal) => canvasesRetrieve(projectId, ref, { signal }),
                                CANVAS_LOOKUP_TIMEOUT_MS
                            )
                            return {
                                key: canvasRecentKey(canvas.id),
                                type: 'canvas',
                                name: canvas.name || 'Untitled canvas',
                                href: urls.canvasDetail(canvas.id),
                                viewedAt: viewed_at,
                            }
                        })
                    )
                    breakpoint()
                    return canvasLookupEntries(views, results, values.recentCanvases).slice(0, TODAY_RECENTS_LIMIT)
                },
            },
        ],
    })),
    reducers({
        recentCanvases: {
            // Drop the previous project's canvases at once. The team listener then loads the new ones.
            loadCurrentTeamSuccess: () => [],
            recordView: (state, { type, ref }) =>
                type === 'canvas'
                    ? state.map((recent) =>
                          recent.key === canvasRecentKey(ref)
                              ? { ...recent, viewedAt: new Date().toISOString() }
                              : recent
                      )
                    : state,
        },
    }),
    selectors({
        recentViewEntries: [
            (s) => [s.recents, s.recentCanvases],
            (recents: FileSystemEntry[], recentCanvases: TodayRecentEntry[]): TodayRecentEntry[] =>
                newestByName(
                    [...recents.flatMap((entry) => fileSystemRecentEntry(entry) ?? []), ...recentCanvases].sort(
                        (first, second) => second.viewedAt.localeCompare(first.viewedAt)
                    ),
                    (recent) => recent.name,
                    (recent) => recent.key,
                    TODAY_RECENTS_LIMIT
                ),
        ],
    }),
    listeners(({ actions }) => ({
        // The team can load after this logic mounts, so the mount-time load finds no project.
        loadCurrentTeamSuccess: ({ currentTeam }) => {
            if (currentTeam) {
                actions.loadRecentCanvases()
            }
        },
        viewLogged: ({ type }) => {
            if (type === 'canvas') {
                actions.loadRecentCanvases()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRecentCanvases()
    }),
])
