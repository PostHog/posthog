import { TODAY_RECENTS_LIMIT, newestByName } from './todayRecentOrder'

export interface TodayRecentEntry {
    key: string
    type: ViewType
    name: string
    href: string
    viewedAt: string
}

function fileSystemRecentEntry(entry: FileSystemEntry): TodayRecentEntry | null {
    const type = baseObjectType(entry.type)
    const href = VIEW_FILE_SYSTEM_TYPES.has(type) ? libraryObjectHref(entry) : null
    return href
        ? {
              key: `${type}-${entry.id}`,
              type: type as ViewType,
              name: unescapePath(splitPath(entry.path).pop() ?? entry.path),
              href,
              viewedAt: entry.last_viewed_at ?? '',
          }
        : null
}

