export const todayLibraryLogic = kea<todayLibraryLogicType>([
    path(['layout', 'today', 'todayLibraryLogic']),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags']] })),
    actions({
        setObjectType: (objectType: string) => ({ objectType }),
        setSearch: (search: string) => ({ search }),
    }),
    reducers({
        objectType: ['', { setObjectType: (_, { objectType }) => objectType }],
        search: ['', { setSearch: (_, { search }) => search }],
    }),
    loaders(({ values }) => {
        const fetchPage = (offset: number): Promise<LibraryObjects> =>
            api.fileSystem
                .list({
                    search: values.search || undefined,
                    notType: 'folder',
                    ...(values.objectType === 'insight'
                        ? { type__startswith: 'insight' }
                        : values.objectType
                          ? { type: values.objectType }
                          : {}),
                    orderBy: '-created_at',
                    offset,
                    limit: LIBRARY_PAGE_SIZE,
                })
                .then((response) => ({ results: response.results, count: response.count }))
        return {
            objects: [
                { results: [], count: 0 } as LibraryObjects,
                {
                    loadObjects: async (_: void, breakpoint) => {
                        await breakpoint(250)
                        const page = await fetchPage(0)
                        breakpoint()
                        return page
                    },
                    loadMoreObjects: async (_: void, breakpoint) => {
                        const page = await fetchPage(values.objects.results.length)
                        breakpoint()
                        return { results: [...values.objects.results, ...page.results], count: page.count }
                    },
                },
            ],
        }
    }),
    reducers({
        loadFailed: [
            false,
            {
                loadObjects: () => false,
                loadObjectsFailure: () => true,
                loadMoreObjectsFailure: () => true,
            },
        ],
    }),
    selectors({
        objectTypes: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): LibraryObjectType[] =>
                sortLibraryTypes(
                    Object.entries(fileSystemTypes)
                        .filter(
                            ([type, entry]) =>
                                !TOOL_FILE_SYSTEM_TYPES.has(type) &&
                                (!('flag' in entry) || !!featureFlags[entry.flag as keyof FeatureFlagsSet])
                        )
                        .map(([value, entry]) => ({
                            value,
                            label: entry.name,
                            pluralLabel: PLURAL_LABELS[value] ?? `${entry.name}s`,
                        }))
                ),
        ],
        objectTypeByValue: [
            (s) => [s.objectTypes],
            (objectTypes: LibraryObjectType[]): Record<string, LibraryObjectType> =>
                Object.fromEntries(objectTypes.map((type) => [type.value, type])),
        ],
        createItemsByType: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): Record<string, FileSystemImport[]> => {
                const byType: Record<string, FileSystemImport[]> = {}
                for (const item of getTreeItemsNew()) {
                    const type = baseObjectType(item.type)
                    if (!item.href || (item.flag && !featureFlags[item.flag as keyof FeatureFlagsSet])) {
                        continue
                    }
                    byType[type] = [...(byType[type] ?? []), item]
                }
                return byType
            },
        ],
        // "All objects" asks for every type, so drop the ones that live in Tools.
        visibleObjects: [
            (s) => [s.objects],
            (objects: LibraryObjects): FileSystemEntry[] =>
                objects.results.filter((entry) => !TOOL_FILE_SYSTEM_TYPES.has(baseObjectType(entry.type))),
        ],
        hasMore: [(s) => [s.objects], (objects: LibraryObjects): boolean => objects.results.length < objects.count],
    }),
    listeners(({ actions }) => ({
        setObjectType: () => actions.loadObjects(),
        setSearch: () => actions.loadObjects(),
    })),
    urlToAction(({ actions, values, cache }) => ({
        [urls.projectHomepage()]: (_, searchParams) => {
            if (searchParams.view !== 'library') {
                return
            }
            const objectType = typeof searchParams.type === 'string' ? searchParams.type : ''
            if (objectType !== values.objectType || !cache.loaded) {
                cache.loaded = true
                actions.setObjectType(objectType)
            }
        },
    })),
])
