export const todayShellLogic = kea<todayShellLogicType>([
    path(['layout', 'today', 'todayShellLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            navigationLogic,
            ['mobileLayout'],
            todaySceneTabsLogic,
            ['sceneTabsMounted'],
        ],
        actions: [router, ['locationChanged']],
    })),
    actions({
        pickPane: (pane: TodayRailPane) => ({ pane }),
        rememberRoutePane: (pane: TodayRailPane) => ({ pane }),
        goBackOnPhone: true,
        setPhonePages: (pages: TodayPhonePage[]) => ({ pages }),
        setMobileSidebarOpen: (open: boolean) => ({ open }),
        setSidebarOpen: (open: boolean) => ({ open }),
        setSidebarWidth: (width: number) => ({ width }),
        toggleSidebar: true,
    }),
    windowValues(() => ({
        phoneLayout: (window: Window) => window.innerWidth < TODAY_PHONE_MAX_WIDTH,
    })),
    reducers({
        // The last pane picked on the rail, or reached through a route that belongs to one, stays open on other pages.
        pickedPane: [
            null as TodayRailPane | null,
            {
                pickPane: (_, { pane }) => pane,
                rememberRoutePane: (_, { pane }) => pane,
            },
        ],
        sidebarOpen: [
            true,
            { persist: true },
            {
                setSidebarOpen: (_, { open }) => open,
            },
        ],
        mobileSidebarOpen: [
            false,
            {
                setMobileSidebarOpen: (_, { open }) => open,
                locationChanged: () => false,
            },
        ],
        phonePages: [
            [] as TodayPhonePage[],
            {
                setPhonePages: (_, { pages }) => pages,
                setMobileSidebarOpen: (state, { open }) => (open ? [] : state),
                locationChanged: (state, { method, pathname, search, hash }) =>
                    nextPhonePages(state, method, { pathname, url: `${pathname}${search}${hash}` }),
            },
        ],
        // The resizer persists the width itself. This copy lets the app layout size the main column from it.
        sidebarWidth: [TODAY_SIDEBAR_DEFAULT_WIDTH, { setSidebarWidth: (_, { width }) => clampSidebarWidth(width) }],
    }),
    selectors({
        routePane: [
            (s) => [router.selectors.location, s.todayWarehouseEnabled],
            (location: { pathname: string }, todayWarehouseEnabled: boolean): TodayRailPane | null =>
                railPaneForPath(location.pathname, todayWarehouseEnabled),
        ],
        activePane: [
            (s) => [s.pickedPane, s.routePane, s.todayWarehouseEnabled],
            (
                rawPickedPane: TodayRailPane | null,
                routePane: TodayRailPane | null,
                todayWarehouseEnabled: boolean
            ): TodayRailPane => {
                // A warehouse pick left over from before the flag went off must not keep the pane open.
                const pickedPane = rawPickedPane === 'warehouse' && !todayWarehouseEnabled ? null : rawPickedPane
                return pickedPane ?? routePane ?? 'home'
            },
        ],
        activePaneHasSidebar: [
            (s) => [s.activePane, s.sceneTabsMounted, s.phoneLayout],
            (activePane: TodayRailPane, sceneTabsMounted: boolean, phoneLayout: boolean): boolean =>
                paneHasSidebar(activePane) || (activePane === 'warehouse' && sceneTabsMounted && !phoneLayout),
        ],
        sidebarInContent: [
            (s) => [s.activePane, s.mobileLayout, s.phoneLayout],
            (activePane: TodayRailPane, mobileLayout: boolean, phoneLayout: boolean): boolean =>
                activePane === 'warehouse' && !mobileLayout && !phoneLayout,
        ],
        leftNavWidth: [
            (s) => [
                s.sidebarOpen,
                s.sidebarWidth,
                s.mobileLayout,
                s.phoneLayout,
                s.activePaneHasSidebar,
                s.sidebarInContent,
            ],
            (
                sidebarOpen: boolean,
                sidebarWidth: number,
                mobileLayout: boolean,
                phoneLayout: boolean,
                activePaneHasSidebar: boolean,
                sidebarInContent: boolean
            ): number =>
                phoneLayout
                    ? 0
                    : TODAY_RAIL_WIDTH +
                      (sidebarOpen && !mobileLayout && activePaneHasSidebar && !sidebarInContent ? sidebarWidth : 0),
        ],
        sidebarVisible: [
            (s) => [s.mobileLayout, s.mobileSidebarOpen, s.sidebarOpen, s.activePaneHasSidebar],
            (
                mobileLayout: boolean,
                mobileSidebarOpen: boolean,
                sidebarOpen: boolean,
                activePaneHasSidebar: boolean
            ): boolean => activePaneHasSidebar && (mobileLayout ? mobileSidebarOpen : sidebarOpen),
        ],
        todayRailEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV],
        ],
        todayWarehouseEnabled: [
            (s) => [s.todayRailEnabled, s.featureFlags],
            (todayRailEnabled: boolean, featureFlags: FeatureFlagsSet): boolean =>
                todayRailEnabled && !!featureFlags[FEATURE_FLAGS.TODAY_RAIL_WAREHOUSE],
        ],
        sceneTabsInSidebar: [
            (s) => [s.todayRailEnabled, s.routePane, s.phoneLayout, s.mobileLayout, s.mobileSidebarOpen, s.sidebarOpen],
            (
                todayRailEnabled: boolean,
                routePane: TodayRailPane | null,
                phoneLayout: boolean,
                mobileLayout: boolean,
                mobileSidebarOpen: boolean,
                sidebarOpen: boolean
            ): boolean =>
                todayRailEnabled &&
                routePane === 'warehouse' &&
                !phoneLayout &&
                (mobileLayout ? mobileSidebarOpen : sidebarOpen),
        ],
        warehouseHeaderShown: [
            (s) => [s.todayRailEnabled, s.routePane],
            (todayRailEnabled: boolean, routePane: TodayRailPane | null): boolean =>
                todayRailEnabled && routePane === 'warehouse',
        ],
        currentWarehouseItem: [
            (s) => [s.routePane, router.selectors.location, s.featureFlags],
            (
                routePane: TodayRailPane | null,
                location: { pathname: string },
                featureFlags: FeatureFlagsSet
            ): WarehouseItem | null =>
                routePane === 'warehouse'
                    ? warehouseItemForLocation(
                          removeProjectIdIfPresent(location.pathname),
                          visibleWarehouseItems(featureFlags)
                      )
                    : null,
        ],
        onAiPage: [
            () => [router.selectors.location],
            (location: { pathname: string }): boolean => {
                const path = removeProjectIdIfPresent(location.pathname)
                return path === urls.ai() || path.startsWith(`${urls.ai()}/`)
            },
        ],
        phoneHeaderHidden: [
            (s) => [s.onAiPage, router.selectors.searchParams, s.todayRailEnabled, s.phoneLayout],
            (
                onAiPage: boolean,
                searchParams: Record<string, any>,
                todayRailEnabled: boolean,
                phoneLayout: boolean
            ): boolean => todayRailEnabled && phoneLayout && onAiPage && !!searchParams.task,
        ],
        // The phone header shows the scene title, so the scene title row leaves it out.
        phoneHeaderShown: [
            (s) => [s.todayRailEnabled, s.phoneLayout, s.phoneHeaderHidden],
            (todayRailEnabled: boolean, phoneLayout: boolean, phoneHeaderHidden: boolean): boolean =>
                todayRailEnabled && phoneLayout && !phoneHeaderHidden,
        ],
        phoneCanGoBack: [(s) => [s.phonePages], (phonePages: TodayPhonePage[]): boolean => phonePages.length > 1],
    }),
    subscriptions(({ actions }) => ({
        mobileLayout: () => actions.setMobileSidebarOpen(false),
    })),
    listeners(({ actions, values, cache }) => ({
        locationChanged: ({ pathname }) => {
            const pane = railPaneForPath(pathname, values.todayWarehouseEnabled)
            if (pane) {
                actions.rememberRoutePane(pane)
            }
        },
        toggleSidebar: () => {
            // The shortcut works on every page, and flipping the saved setting where no sidebar shows would hide it elsewhere.
            if (!values.activePaneHasSidebar) {
                return
            }
            if (values.mobileLayout) {
                actions.setMobileSidebarOpen(!values.mobileSidebarOpen)
            } else {
                actions.setSidebarOpen(!values.sidebarOpen)
            }
        },
        setMobileSidebarOpen: ({ open }) => {
            if (!open) {
                cache.disposables.dispose('drawerEscape')
                return
            }
            cache.disposables.add(() => {
                const onKeyDown = (event: KeyboardEvent): void => {
                    if (event.key === 'Escape' && values.mobileSidebarOpen) {
                        actions.setMobileSidebarOpen(false)
                    }
                }
                window.addEventListener('keydown', onKeyDown)
                return () => window.removeEventListener('keydown', onKeyDown)
            }, 'drawerEscape')
        },
        goBackOnPhone: () => {
            const previous = values.phonePages[values.phonePages.length - 2]
            if (!previous) {
                // A pane without a sidebar has no sheet to open, so an empty sheet would be a dead end.
                if (values.activePaneHasSidebar) {
                    actions.setMobileSidebarOpen(true)
                }
                return
            }
            actions.setPhonePages(values.phonePages.slice(0, -1))
            router.actions.replace(previous.url)
        },
        pickPane: ({ pane }) => {
            // pinned: analytics event name and property. Renaming them breaks dashboards.
            posthog.capture('today rail pane picked', { pane, phone_layout: values.phoneLayout })
            router.actions.push(railPaneHref(pane))
            if (!paneHasSidebar(pane)) {
                actions.setMobileSidebarOpen(false)
                return
            }
            if (values.mobileLayout) {
                actions.setMobileSidebarOpen(true)
            } else {
                actions.setSidebarOpen(true)
            }
        },
    })),
    afterMount(({ actions }) => {
        const { pathname, search, hash } = router.values.location
        actions.setPhonePages([{ pathname, url: `${pathname}${search}${hash}` }])
    }),
])
