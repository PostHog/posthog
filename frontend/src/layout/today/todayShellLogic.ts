export interface todayShellLogicActions {
    locationChanged: ({
        method,
        pathname,
        search,
        searchParams,
        hash,
        hashParams,
        initial,
        url,
        routerState,
    }: LocationChangedPayload) => {
        hash: string
        hashParams: Record<string, any>
        initial: boolean
        method: 'POP' | 'PUSH' | 'REPLACE'
        pathname: string
        routerState: Record<string, any>
        search: string
        searchParams: Record<string, any>
        url: string
    } // router
    pickPane: (pane: TodayRailPane) => {
        pane: TodayRailPane
    }
    setSidebarOpen: (open: boolean) => {
        open: boolean
    }
    toggleSidebar: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayShellLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        routePane: (location: { hash: string; pathname: string; search: string }) => TodayRailPane | null
        activePane: (pickedPane: TodayRailPane | null, routePane: TodayRailPane | null) => TodayRailPane
        leftNavWidth: (sidebarOpen: boolean) => number
    }
}

export type todayShellLogicType = MakeLogicType<
    todayShellLogicValues,
    todayShellLogicActions,
    Record<string, any>,
    todayShellLogicMeta
>

export const todayShellLogic = kea<todayShellLogicType>([
    path(['layout', 'today', 'todayShellLogic']),
    connect(() => ({ actions: [router, ['locationChanged']] })),
    actions({
        pickPane: (pane: TodayRailPane) => ({ pane }),
        setSidebarOpen: (open: boolean) => ({ open }),
        toggleSidebar: true,
    }),
    reducers({
        // The last pane picked on the rail, or reached through a route that belongs to one, stays open on other pages.
        pickedPane: [
            null as TodayRailPane | null,
            {
                pickPane: (_, { pane }) => pane,
                locationChanged: (state, { pathname, search }) => railPaneForPath(pathname, search) ?? state,
            },
        ],
        sidebarOpen: [
            true,
            { persist: true },
            {
                setSidebarOpen: (_, { open }) => open,
                toggleSidebar: (state) => !state,
                pickPane: () => true,
            },
        ],
    }),
    selectors({
        routePane: [
            () => [router.selectors.location],
            (location: { pathname: string; search: string }): TodayRailPane | null =>
                railPaneForPath(location.pathname, location.search),
        ],
        activePane: [
            (s) => [s.pickedPane, s.routePane],
            (pickedPane: TodayRailPane | null, routePane: TodayRailPane | null): TodayRailPane =>
                pickedPane ?? routePane ?? 'home',
        ],
        leftNavWidth: [
            (s) => [s.sidebarOpen],
            (sidebarOpen: boolean): number => TODAY_RAIL_WIDTH + (sidebarOpen ? TODAY_SIDEBAR_WIDTH : 0),
        ],
    }),
    listeners(({ values }) => ({
        pickPane: ({ pane }) => {
            if (pane === 'home' && values.routePane !== 'home') {
                router.actions.push(urls.projectHomepage())
            }
            if (pane === 'library' && values.routePane !== 'library') {
                router.actions.push(libraryUrl())
            }
        },
    })),
])
