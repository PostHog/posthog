/**
 * Pins for every Today sidebar pane. Pins are the project tree's shortcuts, which the classic navigation lists as
 * Starred, so a pin made here shows in every other place that lists them, and the reverse. Each pane picks the pins
 * of its own types from `shortcutData`.
 */
export const sidebarPinsLogic = kea<sidebarPinsLogicType>([
    path(['layout', 'today', 'sidebar', 'sidebarPinsLogic']),
    connect(() => ({
        values: [projectTreeDataLogic, ['shortcutData', 'shortcutDataLoading']],
        actions: [projectTreeDataLogic, ['addShortcutItem', 'deleteShortcut', 'reorderShortcuts']],
    })),
    actions({
        movePinned: (shortcutId: string, overShortcutId: string) => ({ shortcutId, overShortcutId }),
        togglePinned: (target: PinTarget) => ({ target }),
        setRecentlyPinned: (key: string) => ({ key }),
        clearRecentlyPinned: true,
    }),
    reducers({
        // The pin a sidebar animates in once, so a person sees where the new pin went.
        recentlyPinnedKey: [
            null as string | null,
            {
                setRecentlyPinned: (_, { key }) => key,
                clearRecentlyPinned: () => null,
            },
        ],
    }),
    selectors({
        pinnedShortcutIds: [
            (s) => [s.shortcutData],
            (shortcutData: FileSystemEntry[]): Map<string, string> => {
                const ids = new Map<string, string>()
                for (const shortcut of shortcutData) {
                    if (!shortcut.id) {
                        continue
                    }
                    // A cohort starred in the classic navigation has a ref, and its People pin has only the href.
                    // Both keys find the same shortcut, so either pin control can remove it.
                    for (const refOrHref of [shortcut.ref, shortcut.href]) {
                        if (refOrHref) {
                            ids.set(pinKey(shortcut.type, refOrHref), shortcut.id)
                        }
                    }
                }
                return ids
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        movePinned: ({ shortcutId, overShortcutId }) => {
            // Each pane's pins are a subset of all shortcuts, so the move happens in the full list to keep the others in place.
            const ids = values.shortcutData.map((shortcut) => shortcut.id).filter((id): id is string => !!id)
            const from = ids.indexOf(shortcutId)
            const to = ids.indexOf(overShortcutId)
            if (from < 0 || to < 0 || from === to) {
                return
            }
            ids.splice(to, 0, ...ids.splice(from, 1))
            actions.reorderShortcuts(ids)
        },
        togglePinned: ({ target }) => {
            // Every pin control is disabled while a change saves. This also stops a repeated dispatch.
            if (values.shortcutDataLoading) {
                return
            }
            const key = pinTargetKey(target)
            const shortcutId = values.pinnedShortcutIds.get(key)
            if (shortcutId) {
                actions.deleteShortcut(shortcutId, UNPINNED_TOAST)
                return
            }
            actions.setRecentlyPinned(key)
            if (target.type === 'folder' && target.ref) {
                // A folder shortcut keeps its path as ref, so a rename moves the pin with the folder.
                actions.addShortcutItem({ path: target.ref, type: 'folder' } as FileSystemEntry, PINNED_TOAST)
            } else {
                actions.addShortcutItem(
                    {
                        path: escapePath(target.name),
                        type: target.type,
                        ref: target.ref,
                        href: target.href,
                    } as FileSystemEntry,
                    PINNED_TOAST
                )
            }
        },
    })),
])
