import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { projectTreeDataLogic } from '~/layout/panel-layout/ProjectTree/projectTreeDataLogic'
import { escapePath } from '~/layout/panel-layout/ProjectTree/utils'
import { FileSystemEntry } from '~/queries/schema/schema-general'

export const PINNED_TOAST = 'Pinned to sidebar'
export const UNPINNED_TOAST = 'Unpinned from sidebar'

/** A thing a person can pin. An object pins by its `ref`, and a page with no file system row pins by its `href`. */
export interface PinTarget {
    type: string
    ref?: string
    name: string
    href?: string
}

/** One key per pinnable thing. `insight/trends` and `insight` share a key, since the shortcut keeps whichever it was given. */
export function pinKey(type: string | undefined, refOrHref: string): string {
    return `${type?.split('/')[0] ?? ''}:${refOrHref}`
}

export function pinTargetKey(target: PinTarget): string {
    return pinKey(target.type, target.ref ?? target.href ?? '')
}

/** A chat pins on its task rather than as a shortcut, but its new pin slides in the same way. */
export function sessionPinKey(sessionId: string): string {
    return pinKey('session', sessionId)
}

