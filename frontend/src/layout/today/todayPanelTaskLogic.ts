import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'

import { taskLogic } from 'products/posthog_ai/frontend/api/logics'

import type { Task } from '../../../../products/posthog_ai/frontend/types/taskTypes'
import type { TaskRun } from '../../../../products/posthog_ai/frontend/types/taskTypes'
import { todayAiChatLogic } from './todayAiChatLogic'

export interface TodayPanelTaskLogicProps {
    taskId: string
    /** The run the panel shows, which can be older than the task's latest. */
    runId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayPanelTaskLogicValues {
    task: Task | null // taskLogic
    taskLoading: boolean // taskLogic
    run: Awaited<ReturnType<typeof api.tasks.runs.get>> | null
    runLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayPanelTaskLogicActions {
    loadTask: () => any // taskLogic
    startNewChat: () => {
        value: true
    } // todayAiChatLogic
    archive: () => {
        value: true
    }
    loadRun: () => any
    loadRunFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRunSuccess: (
        run: TaskRun,
        payload?: any
    ) => {
        run: TaskRun
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayPanelTaskLogicMeta {
    key: string
}

export type todayPanelTaskLogicType = MakeLogicType<
    todayPanelTaskLogicValues,
    todayPanelTaskLogicActions,
    TodayPanelTaskLogicProps,
    todayPanelTaskLogicMeta
>

export const todayPanelTaskLogic = kea<todayPanelTaskLogicType>([
    props({} as TodayPanelTaskLogicProps),
    key((props) => `${props.taskId}:${props.runId}`),
    path((key) => ['layout', 'today', 'todayPanelTaskLogic', key]),
    connect((props: TodayPanelTaskLogicProps) => ({
        values: [taskLogic({ taskId: props.taskId }), ['task', 'taskLoading']],
        actions: [taskLogic({ taskId: props.taskId }), ['loadTask'], todayAiChatLogic, ['startNewChat']],
    })),
    actions({
        archive: true,
    }),
    loaders(({ props }) => ({
        run: [
            null as Awaited<ReturnType<typeof api.tasks.runs.get>> | null,
            {
                loadRun: async () => await api.tasks.runs.get(props.taskId, props.runId),
            },
        ],
    })),
    listeners(({ actions, props }) => ({
        archive: async () => {
            try {
                await taskLogic({ taskId: props.taskId }).asyncActions.deleteTask({ leavePage: false })
            } catch {
                // The loader reports the failure. The panel stays on the task, which is still there.
                return
            }
            // An archived task has nothing left to show, so the panel moves on to a new chat.
            actions.startNewChat()
        },
    })),
    afterMount(({ actions, values }) => {
        if (!values.task && !values.taskLoading) {
            actions.loadTask()
        }
        actions.loadRun()
    }),
])
