export const todayAnalyticsLogic = kea<todayAnalyticsLogicType>([
    path(['layout', 'today', 'todayAnalyticsLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            teamLogic,
            ['currentTeamId'],
            analyticsFeedLogic,
            ['sources', 'spaceNames'],
        ],
        actions: [
            analyticsFeedLogic,
            ['ensureFeed', 'refreshFeed', 'sourceRefreshed'],
            projectTreeDataLogic,
            ['createSavedItem'],
            router,
            ['locationChanged'],
        ],
    })),
    actions({
        toggleSection: (section: TodayAnalyticsSection) => ({ section }),
        setNewFolderDialogOpen: (open: boolean) => ({ open }),
        createFolder: (name: string) => ({ name }),
        folderCreated: true,
        folderCreationFailed: true,
        setQuery: (query: string) => ({ query }),
        setSearch: (search: string) => ({ search }),
        loadRecentAnalytics: true,
        /** The open canvas reports whether its agent or a build is at work, which it knows exactly. Null when it closes. */
        setOpenCanvasBuilding: (canvasId: string, building: boolean | null) => ({ canvasId, building }),
    }),
    loaders(({ values }) => ({
        // A canvas on its first build has nothing to show until its first version, so until then its run
        // says whether the agent is building it. Later runs stay open after the agent's turn, so they cannot.
        firstBuilds: [
            {} as Record<string, FirstBuildState>,
            {
                loadFirstBuilds: async (_: void, breakpoint) => {
                    const projectId = values.currentTeamId ? String(values.currentTeamId) : null
                    const pending = values.allAnalytics.items.filter((item) => item.firstBuildTaskId)
                    if (!projectId || !pending.length) {
                        return {}
                    }
                    const results = await Promise.allSettled(
                        pending.map(async (item): Promise<[string, FirstBuildState]> => {
                            const [canvas, task] = await Promise.all([
                                canvasesRetrieve(projectId, item.id),
                                tasksRetrieve(projectId, item.firstBuildTaskId as string),
                            ])
                            return [
                                item.id,
                                { hasVersion: !!canvas.current_version_id, runStatus: task.latest_run?.status ?? null },
                            ]
                        })
                    )
                    breakpoint()
                    // A canvas whose lookup failed shows no spinner rather than holding up the rest.
                    return Object.fromEntries(
                        results.flatMap((result) => (result.status === 'fulfilled' ? [result.value] : []))
                    )
                },
            },
        ],
    })),
    reducers({
        // pinned: storage key for the persisted sections. Renaming it reopens everyone's sections.
        collapsedSections: [
            DEFAULT_COLLAPSED_SECTIONS,
            { persist: true },
            {
                toggleSection: (state, { section }) =>
                    state.includes(section) ? state.filter((id) => id !== section) : [...state, section],
            },
        ],
        newFolderDialogOpen: [
            false,
            {
                setNewFolderDialogOpen: (_, { open }) => open,
                folderCreated: () => false,
            },
        ],
        creatingFolder: [
            false,
            {
                createFolder: () => true,
                folderCreated: () => false,
                folderCreationFailed: () => false,
            },
        ],
        query: ['', { setQuery: (_, { query }) => query }],
        search: ['', { setSearch: (_, { search }) => search }],
        openCanvasBuilding: [
            {} as Record<string, boolean>,
            {
                setOpenCanvasBuilding: (state, { canvasId, building }) => {
                    const { [canvasId]: _, ...rest } = state
                    return building === null ? rest : { ...rest, [canvasId]: building }
                },
            },
        ],
    }),
    selectors({
        fromPostHog: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): FromPostHogItem[] => fromPostHogItems(featureFlags),
        ],
        allAnalytics: [
            (s) => [s.sources, s.spaceNames, s.currentTeamId],
            (
                sources: Record<string, AnalyticsSourceState>,
                spaceNames: Record<string, string>,
                currentTeamId: number | null
            ): AnalyticsFeed => selectAnalyticsFeed(sources, spaceNames, currentTeamId, EMPTY_ANALYTICS_FEED_QUERY),
        ],
        searchQuery: [
            (s) => [s.search],
            (search: string): AnalyticsFeedQuery => ({ ...EMPTY_ANALYTICS_FEED_QUERY, search: search.trim() }),
        ],
        searchFeed: [
            (s) => [s.sources, s.spaceNames, s.currentTeamId, s.searchQuery],
            (
                sources: Record<string, AnalyticsSourceState>,
                spaceNames: Record<string, string>,
                currentTeamId: number | null,
                searchQuery: AnalyticsFeedQuery
            ): AnalyticsFeed => selectAnalyticsFeed(sources, spaceNames, currentTeamId, searchQuery),
        ],
        // While the server search is on its way, the rows already loaded answer the query by name.
        searchResults: [
            (s) => [s.searchFeed, s.allAnalytics, s.query, s.search],
            (
                searchFeed: AnalyticsFeed,
                allAnalytics: AnalyticsFeed,
                query: string,
                search: string
            ): AnalyticsItem[] => {
                if (!query.trim()) {
                    return []
                }
                if (searchFeed.initialized && query.trim() === search.trim()) {
                    return searchFeed.items
                }
                return allAnalytics.items.filter((item) => matchesPaneQuery(item.name, query))
            },
        ],
        buildingIds: [
            (s) => [s.allAnalytics, s.firstBuilds, s.openCanvasBuilding],
            (
                allAnalytics: AnalyticsFeed,
                firstBuilds: Record<string, FirstBuildState>,
                openCanvasBuilding: Record<string, boolean>
            ): string[] =>
                allAnalytics.items
                    .filter((item) => {
                        if (item.id in openCanvasBuilding) {
                            return openCanvasBuilding[item.id]
                        }
                        const firstBuild = firstBuilds[item.id]
                        return (
                            !!item.firstBuildTaskId &&
                            !!firstBuild &&
                            !firstBuild.hasVersion &&
                            !!firstBuild.runStatus &&
                            !TERMINAL_RUN_STATUSES.has(firstBuild.runStatus)
                        )
                    })
                    .map((item) => item.id),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        toggleSection: ({ section }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics section toggled', {
                section,
                open: !values.collapsedSections.includes(section),
            })
        },
        createFolder: async ({ name }) => {
            const path = name.trim()
            if (!path) {
                actions.folderCreationFailed()
                return
            }
            try {
                // The project tree keeps the rows, so the new folder shows wherever the tree is open.
                const entry = await api.fileSystem.create({ path, type: 'folder' } as FileSystemEntry)
                actions.createSavedItem(entry)
                actions.folderCreated()
                // pinned: analytics event name. Renaming it breaks dashboards.
                posthog.capture('analytics folder created')
                toast.success({ title: 'Folder created' })
            } catch {
                actions.folderCreationFailed()
                toast.error({ title: 'Couldn’t create the folder. Try again.' })
            }
        },
        loadRecentAnalytics: () => {
            actions.refreshFeed(EMPTY_ANALYTICS_FEED_QUERY)
            if (values.search.trim()) {
                actions.refreshFeed(values.searchQuery)
            }
        },
        sourceRefreshed: () => {
            if (values.allAnalytics.initialized && !values.allAnalytics.loading) {
                actions.loadFirstBuilds()
            }
        },
        setQuery: async ({ query }, breakpoint) => {
            if (query.trim() !== values.search) {
                await breakpoint(query.trim() ? 200 : 0)
                actions.setSearch(query.trim())
            }
        },
        setSearch: ({ search }) => {
            if (search.trim()) {
                actions.ensureFeed(values.searchQuery, ANALYTICS_FEED_PAGE_SIZE)
            }
        },
        loadFirstBuildsSuccess: ({ firstBuilds }) => {
            const building = Object.values(firstBuilds).filter(
                (build) => !build.hasVersion && !!build.runStatus && !TERMINAL_RUN_STATUSES.has(build.runStatus)
            )
            // A first version changes the row, so the list reloads once the build is done.
            if (Object.values(firstBuilds).some((build) => build.hasVersion)) {
                actions.loadRecentAnalytics()
                return
            }
            if (building.length && !values.allAnalytics.loading) {
                cache.disposables.add(() => {
                    const id = setTimeout(() => actions.loadFirstBuilds(), FIRST_BUILD_POLL_MS)
                    return () => clearTimeout(id)
                }, 'firstBuildPoll')
            } else {
                cache.disposables.dispose('firstBuildPoll')
            }
        },
        locationChanged: ({ pathname }) => {
            // Creating, restoring or opening something lands on a new Analytics path, so the lists stay current.
            // Search and hash changes, such as dashboard filters, keep the path and do not reload.
            if (pathname !== cache.lastPathname && railPaneForPath(pathname) === 'analytics') {
                actions.loadRecentAnalytics()
            }
            cache.lastPathname = pathname
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.lastPathname = router.values.location.pathname
        actions.loadRecentAnalytics()
    }),
])
