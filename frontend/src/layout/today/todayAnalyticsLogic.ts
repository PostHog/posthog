export const todayAnalyticsLogic = kea<todayAnalyticsLogicType>([
    path(['layout', 'today', 'todayAnalyticsLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            recentItemsModel,
            ['recents', 'recentsHasLoaded'],
            analyticsPinnedLogic,
            ['pinnedShortcutIds'],
            teamLogic,
            ['currentProjectId'],
        ],
        actions: [projectTreeDataLogic, ['createSavedItem']],
    })),
    actions({
        loadSidebar: true,
        resetSidebar: (previous: AnalyticsSidebarLayoutApi) => ({ previous }),
        restoreSidebar: (layout: AnalyticsSidebarLayoutApi) => ({ layout }),
        sidebarReadFailed: true,
        toggleSection: (section: string) => ({ section }),
        setSearchQuery: (searchQuery: string) => ({ searchQuery }),
        storeRecentAnalytics: (items: AnalyticsItem[]) => ({ items }),
        setNewFolderDialogOpen: (open: boolean, parent: string | null = null) => ({ open, parent }),
        createFolder: (name: string) => ({ name }),
        folderCreated: true,
        folderCreationFailed: true,
    }),
    loaders(({ actions, cache, values }) => ({
        sidebar: [
            null as AnalyticsSidebarApi | null,
            {
                requestSidebar: async (request: SidebarRequest, breakpoint) => {
                    const previousSidebar = (): AnalyticsSidebarApi =>
                        values.sidebar ?? values.savedSidebar ?? DEFAULT_ANALYTICS_SIDEBAR
                    if (!values.sidebarCustomizationEnabled) {
                        return previousSidebar()
                    }
                    const flagGeneration = cache.sidebarFlagGeneration ?? 0
                    const canApply = (): boolean =>
                        values.sidebarCustomizationEnabled && flagGeneration === (cache.sidebarFlagGeneration ?? 0)
                    const teamId = String(values.currentProjectId)
                    const isWrite = request.operation !== 'load'
                    let response: Promise<AnalyticsSidebarApi>
                    if (isWrite) {
                        cache.sidebarPendingWrites = (cache.sidebarPendingWrites ?? 0) + 1
                        response = (cache.sidebarWriteTail ?? Promise.resolve()).then(() =>
                            !canApply()
                                ? previousSidebar()
                                : request.operation === 'reset'
                                  ? uiCustomizationAnalyticsSidebarDestroy(teamId)
                                  : uiCustomizationAnalyticsSidebarUpdate(teamId, { layout: request.layout })
                        )
                        // A failed write must not prevent a later Reset or Undo from reaching the server.
                        cache.sidebarWriteTail = response.catch(() => undefined)
                    } else {
                        response = uiCustomizationAnalyticsSidebarRetrieve(teamId)
                    }
                    try {
                        const sidebar = await response
                        breakpoint()
                        cache.sidebarCompletedRequest = canApply() ? request : null
                        return canApply() ? sidebar : previousSidebar()
                    } catch (error) {
                        breakpoint()
                        if (!canApply()) {
                            cache.sidebarCompletedRequest = null
                            return previousSidebar()
                        }
                        if (request.operation === 'load') {
                            actions.sidebarReadFailed()
                        } else {
                            cache.sidebarReloadAfterWrite = true
                            toast.error({
                                title:
                                    request.operation === 'reset'
                                        ? 'Couldn’t reset the sidebar. Try again.'
                                        : 'Couldn’t bring back your sidebar. Ask PostHog AI to build it again.',
                            })
                        }
                        throw error
                    } finally {
                        if (isWrite) {
                            cache.sidebarPendingWrites -= 1
                        }
                    }
                },
            },
        ],
    })),
    reducers({
        // pinned: storage key for the saved layout. Renaming it makes everyone's sidebar wait for its request once.
        savedSidebar: [
            null as AnalyticsSidebarApi | null,
            TODAY_USER_PERSIST_OPTIONS,
            {
                requestSidebarSuccess: (_, { sidebar }) => sidebar,
            },
        ],
        sidebarFailed: [
            false,
            { requestSidebar: () => false, requestSidebarSuccess: () => false, sidebarReadFailed: () => true },
        ],
        // pinned: storage key for the saved Recents list. Renaming it makes everyone's Recents pop in once more.
        savedRecentAnalytics: [
            [] as AnalyticsItem[],
            TODAY_USER_PERSIST_OPTIONS,
            { storeRecentAnalytics: (_, { items }) => items },
        ],
        searchQuery: ['', { setSearchQuery: (_, { searchQuery }) => searchQuery }],
        // pinned: storage key for the persisted sections. Renaming it reopens everyone's sections.
        collapsedSections: [
            DEFAULT_COLLAPSED_SECTIONS,
            { persist: true },
            {
                toggleSection: (state, { section }) =>
                    state.includes(section) ? state.filter((id) => id !== section) : [...state, section],
            },
        ],
        // The collection a folder is created in, or null for a new top-level collection.
        newFolderParent: [null as string | null, { setNewFolderDialogOpen: (_, { parent }) => parent }],
        newFolderDialogOpen: [
            false,
            {
                setNewFolderDialogOpen: (_, { open }) => open,
                folderCreated: () => false,
            },
        ],
        creatingFolder: [
            false,
            {
                createFolder: () => true,
                folderCreated: () => false,
                folderCreationFailed: () => false,
            },
        ],
    }),
    selectors({
        sidebarCustomizationEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => featureFlags[FEATURE_FLAGS.UI_CUSTOMIZATION] === true,
        ],
        shownSidebar: [
            (s) => [s.sidebar, s.savedSidebar, s.sidebarCustomizationEnabled],
            (sidebar: AnalyticsSidebarApi | null, savedSidebar: AnalyticsSidebarApi | null, enabled: boolean) =>
                enabled ? selectShownSidebar(sidebar, savedSidebar) : DEFAULT_ANALYTICS_SIDEBAR,
        ],
        sidebarLayout: [(s) => [s.shownSidebar], (shownSidebar: AnalyticsSidebarApi) => shownSidebar.layout],
        sidebarCustomized: [(s) => [s.shownSidebar], (shownSidebar: AnalyticsSidebarApi) => shownSidebar.customized],
        /** Whether a row's label matches the pane search. Every row matches while the search is empty. */
        matchesSearch: [
            (s) => [s.searchQuery],
            (searchQuery: string) =>
                (label: string): boolean =>
                    matchesPaneQuery(label, searchQuery),
        ],
        /** A search opens every section, so no match hides in a collapsed one. */
        isSectionOpen: [
            (s) => [s.collapsedSections, s.searchQuery],
            (collapsedSections: string[], searchQuery: string) =>
                (section: string): boolean =>
                    searchQuery.trim() !== '' || !collapsedSections.includes(section),
        ],
        fromPostHog: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): FromPostHogItem[] => fromPostHogItems(featureFlags),
        ],
        // The app loads recently viewed items once and keeps them, so this section needs no request of its own.
        // Pinned items already show in the Pinned section, so Recents leaves them out before it applies the limit.
        freshRecentAnalytics: [
            (s) => [s.recents, s.pinnedShortcutIds],
            (recents: FileSystemEntry[], pinnedShortcutIds: Map<string, string>): AnalyticsItem[] =>
                newestByName(
                    recents.flatMap((entry) => {
                        const item = fileSystemEntryToAnalytics(entry)
                        return item && !pinnedShortcutIds.has(pinKey(item.type, item.id)) ? [item] : []
                    }),
                    (item) => item.name,
                    (item) => pinKey(item.type, item.id),
                    TODAY_ANALYTICS_RECENTS_LIMIT
                ),
        ],
        // The saved list covers only the wait for the shared list. Once it has loaded, even empty, it is the answer.
        recentAnalytics: [
            (s) => [s.recentsHasLoaded, s.freshRecentAnalytics, s.savedRecentAnalytics, s.pinnedShortcutIds],
            (
                recentsHasLoaded: boolean,
                fresh: AnalyticsItem[],
                saved: AnalyticsItem[],
                pinnedShortcutIds: Map<string, string>
            ): AnalyticsItem[] =>
                recentsHasLoaded ? fresh : saved.filter((item) => !pinnedShortcutIds.has(pinKey(item.type, item.id))),
        ],
    }),
    listeners(({ actions, asyncActions, cache, values }) => ({
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
            const enabled = values.sidebarCustomizationEnabled
            if (enabled !== cache.sidebarCustomizationEnabled) {
                cache.sidebarCustomizationEnabled = enabled
                cache.sidebarFlagGeneration = (cache.sidebarFlagGeneration ?? 0) + 1
                if (enabled) {
                    actions.loadSidebar()
                }
            }
        },
        loadSidebar: () => {
            if (!values.sidebarCustomizationEnabled) {
                return
            }
            if (cache.sidebarPendingWrites) {
                cache.sidebarReloadAfterWrite = true
                return
            }
            return asyncActions.requestSidebar({ operation: 'load' })
        },
        resetSidebar: ({ previous }) => {
            if (values.sidebarCustomizationEnabled) {
                return asyncActions.requestSidebar({ operation: 'reset', previous })
            }
        },
        restoreSidebar: ({ layout }) => {
            if (values.sidebarCustomizationEnabled) {
                return asyncActions.requestSidebar({ operation: 'restore', layout })
            }
        },
        requestSidebarSuccess: ({ payload }) => {
            if (
                values.sidebarCustomizationEnabled &&
                payload?.operation === 'reset' &&
                cache.sidebarCompletedRequest === payload
            ) {
                const projectId = values.currentProjectId
                // pinned: analytics event name. Renaming it breaks dashboards.
                posthog.capture('analytics sidebar reset')
                toast.success({
                    title: 'Sidebar reset to the default',
                    action: {
                        label: 'Undo',
                        onClick: async () => {
                            const logic = todayAnalyticsLogic()
                            const unmount = logic.mount()
                            try {
                                if (logic.values.currentProjectId === projectId) {
                                    await logic.asyncActions.restoreSidebar(payload.previous)
                                }
                            } finally {
                                unmount()
                            }
                        },
                    },
                })
            }
            if (!cache.sidebarPendingWrites && cache.sidebarReloadAfterWrite) {
                cache.sidebarReloadAfterWrite = false
                actions.loadSidebar()
            }
        },
        requestSidebarFailure: () => {
            if (!cache.sidebarPendingWrites && cache.sidebarReloadAfterWrite) {
                cache.sidebarReloadAfterWrite = false
                actions.loadSidebar()
            }
        },
        toggleSection: ({ section }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics section toggled', {
                section,
                open: !values.collapsedSections.includes(section),
            })
        },
        createFolder: async ({ name }) => {
            const parent = values.newFolderParent
            // One name is one segment: a slash in it must not create a nested folder.
            const path = parent ? `${parent}/${escapePath(name.trim())}` : escapePath(name.trim())
            if (!name.trim()) {
                actions.folderCreationFailed()
                return
            }
            try {
                // The project tree keeps the rows, so the new folder shows wherever the tree is open.
                const entry = await api.fileSystem.create({ path, type: 'folder' } as FileSystemEntry)
                actions.createSavedItem(entry)
                actions.folderCreated()
                // pinned: analytics event name. Renaming it breaks dashboards.
                posthog.capture('analytics folder created', { nested: parent !== null })
                toast.success({ title: parent ? 'Folder created' : 'Collection created' })
            } catch {
                actions.folderCreationFailed()
                toast.error({
                    title: parent
                        ? 'Couldn’t create the folder. Try again.'
                        : 'Couldn’t create the collection. Try again.',
                })
            }
        },
    })),
    afterMount(({ actions, cache, values }) => {
        cache.sidebarCustomizationEnabled = values.sidebarCustomizationEnabled
        actions.loadSidebar()
    }),
    subscriptions(({ actions, values }) => ({
        // Saves what the section shows, so the next page load starts from it. Before the shared list loads, the
        // section shows a filtered copy of the saved list, and saving that copy would start the subscription again.
        recentAnalytics: (items: AnalyticsItem[]) => {
            if (values.recentsHasLoaded) {
                actions.storeRecentAnalytics(items)
            }
        },
    })),
])
