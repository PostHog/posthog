import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { subscriptions } from 'kea-subscriptions'
import posthog from 'posthog-js'

import { toast } from '@posthog/quill'

import api from 'lib/api'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { getCurrentTeamIdOrNone, getCurrentUserIdOrNone } from 'lib/utils/getAppContext'
import {
    AnalyticsItem,
    FromPostHogItem,
    fileSystemEntryToAnalytics,
    fromPostHogItems,
} from 'scenes/analytics/analyticsUtils'

import { projectTreeDataLogic } from '~/layout/panel-layout/ProjectTree/projectTreeDataLogic'
import { escapePath } from '~/layout/panel-layout/ProjectTree/utils'
import { recentItemsModel } from '~/models/recentItemsModel'
import { FileSystemEntry } from '~/queries/schema/schema-general'

// pinned: persisted section ids and the `section` property of `analytics section toggled`.
export type TodayAnalyticsSection = 'browse' | 'recents' | 'monitor' | 'by-posthog'

export const DEFAULT_COLLAPSED_SECTIONS: TodayAnalyticsSection[] = []

export const TODAY_ANALYTICS_RECENTS_LIMIT = 3

// The last Recents list stays in the browser so it shows on first paint. It belongs to one person in one project,
// and without both ids nothing persists, so one account never sees another's.
const RECENTS_TEAM_ID = getCurrentTeamIdOrNone()
const RECENTS_USER_ID = getCurrentUserIdOrNone()
const RECENTS_PERSIST_OPTIONS =
    RECENTS_TEAM_ID && RECENTS_USER_ID
        ? { persist: true, prefix: `${RECENTS_TEAM_ID}__${RECENTS_USER_ID}__` }
        : { persist: false }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayAnalyticsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    recents: FileSystemEntry[] // recentItemsModel
    recentsHasLoaded: boolean // recentItemsModel
    collapsedSections: TodayAnalyticsSection[]
    creatingFolder: boolean
    freshRecentAnalytics: AnalyticsItem[]
    fromPostHog: FromPostHogItem[]
    newFolderDialogOpen: boolean
    newFolderParent: string | null
    recentAnalytics: AnalyticsItem[]
    savedRecentAnalytics: AnalyticsItem[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayAnalyticsLogicActions {
    createSavedItem: (savedItem: FileSystemEntry) => {
        savedItem: FileSystemEntry
    } // projectTreeDataLogic
    createFolder: (name: string) => {
        name: string
    }
    folderCreated: () => {
        value: true
    }
    folderCreationFailed: () => {
        value: true
    }
    setNewFolderDialogOpen: (
        open: boolean,
        parent?: string | null
    ) => {
        open: boolean
        parent: string | null
    }
    storeRecentAnalytics: (items: AnalyticsItem[]) => {
        items: AnalyticsItem[]
    }
    toggleSection: (section: TodayAnalyticsSection) => {
        section: TodayAnalyticsSection
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayAnalyticsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        fromPostHog: (featureFlags: FeatureFlagsSet) => FromPostHogItem[]
        freshRecentAnalytics: (recents: FileSystemEntry[]) => AnalyticsItem[]
        recentAnalytics: (
            recentsHasLoaded: boolean,
            freshRecentAnalytics: AnalyticsItem[],
            savedRecentAnalytics: AnalyticsItem[]
        ) => AnalyticsItem[]
    }
}

export type todayAnalyticsLogicType = MakeLogicType<
    todayAnalyticsLogicValues,
    todayAnalyticsLogicActions,
    Record<string, any>,
    todayAnalyticsLogicMeta
>

export const todayAnalyticsLogic = kea<todayAnalyticsLogicType>([
    path(['layout', 'today', 'todayAnalyticsLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], recentItemsModel, ['recents', 'recentsHasLoaded']],
        actions: [projectTreeDataLogic, ['createSavedItem']],
    })),
    actions({
        toggleSection: (section: TodayAnalyticsSection) => ({ section }),
        storeRecentAnalytics: (items: AnalyticsItem[]) => ({ items }),
        setNewFolderDialogOpen: (open: boolean, parent: string | null = null) => ({ open, parent }),
        createFolder: (name: string) => ({ name }),
        folderCreated: true,
        folderCreationFailed: true,
    }),
    reducers({
        // pinned: storage key for the saved Recents list. Renaming it makes everyone's Recents pop in once more.
        savedRecentAnalytics: [
            [] as AnalyticsItem[],
            RECENTS_PERSIST_OPTIONS,
            { storeRecentAnalytics: (_, { items }) => items },
        ],
        // pinned: storage key for the persisted sections. Renaming it reopens everyone's sections.
        collapsedSections: [
            DEFAULT_COLLAPSED_SECTIONS,
            { persist: true },
            {
                toggleSection: (state, { section }) =>
                    state.includes(section) ? state.filter((id) => id !== section) : [...state, section],
            },
        ],
        // The collection a folder is created in, or null for a new top-level collection.
        newFolderParent: [null as string | null, { setNewFolderDialogOpen: (_, { parent }) => parent }],
        newFolderDialogOpen: [
            false,
            {
                setNewFolderDialogOpen: (_, { open }) => open,
                folderCreated: () => false,
            },
        ],
        creatingFolder: [
            false,
            {
                createFolder: () => true,
                folderCreated: () => false,
                folderCreationFailed: () => false,
            },
        ],
    }),
    selectors({
        fromPostHog: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): FromPostHogItem[] => fromPostHogItems(featureFlags),
        ],
        // The app loads recently viewed items once and keeps them, so this section needs no request of its own.
        freshRecentAnalytics: [
            (s) => [s.recents],
            (recents: FileSystemEntry[]): AnalyticsItem[] =>
                recents
                    .flatMap((entry) => {
                        const item = fileSystemEntryToAnalytics(entry)
                        return item ? [item] : []
                    })
                    .slice(0, TODAY_ANALYTICS_RECENTS_LIMIT),
        ],
        // The saved list covers only the wait for the shared list. Once it has loaded, even empty, it is the answer.
        recentAnalytics: [
            (s) => [s.recentsHasLoaded, s.freshRecentAnalytics, s.savedRecentAnalytics],
            (recentsHasLoaded: boolean, fresh: AnalyticsItem[], saved: AnalyticsItem[]): AnalyticsItem[] =>
                recentsHasLoaded ? fresh : saved,
        ],
    }),
    listeners(({ actions, values }) => ({
        toggleSection: ({ section }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics section toggled', {
                section,
                open: !values.collapsedSections.includes(section),
            })
        },
        createFolder: async ({ name }) => {
            const parent = values.newFolderParent
            // One name is one segment: a slash in it must not create a nested folder.
            const path = parent ? `${parent}/${escapePath(name.trim())}` : escapePath(name.trim())
            if (!name.trim()) {
                actions.folderCreationFailed()
                return
            }
            try {
                // The project tree keeps the rows, so the new folder shows wherever the tree is open.
                const entry = await api.fileSystem.create({ path, type: 'folder' } as FileSystemEntry)
                actions.createSavedItem(entry)
                actions.folderCreated()
                // pinned: analytics event name. Renaming it breaks dashboards.
                posthog.capture('analytics folder created', { nested: parent !== null })
                toast.success({ title: parent ? 'Folder created' : 'Collection created' })
            } catch {
                actions.folderCreationFailed()
                toast.error({
                    title: parent
                        ? 'Couldn’t create the folder. Try again.'
                        : 'Couldn’t create the collection. Try again.',
                })
            }
        },
    })),
    subscriptions(({ actions }) => ({
        // Saves what the section shows, so the next page load starts from it.
        recentAnalytics: (items: AnalyticsItem[]) => actions.storeRecentAnalytics(items),
    })),
])
