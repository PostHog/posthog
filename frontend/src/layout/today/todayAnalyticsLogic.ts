export function selectShownSidebar(
    sidebar: AnalyticsSidebarApi | null,
    savedSidebar: AnalyticsSidebarApi | null
): AnalyticsSidebarApi {
    return sidebar ?? savedSidebar ?? DEFAULT_ANALYTICS_SIDEBAR
}

