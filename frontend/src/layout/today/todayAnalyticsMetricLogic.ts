import { MakeLogicType, afterMount, connect, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { METRIC_SUMMARY_DEFAULT, computeMetricSummary } from 'lib/components/Metric/metricSummary'
import { teamLogic } from 'scenes/teamLogic'

import { TrendsFilter } from '~/queries/schema/schema-general'
import { TrendResult } from '~/types'

import { insightsList } from 'products/product_analytics/frontend/generated/api'
import type { InsightApi } from 'products/product_analytics/frontend/generated/api.schemas'

export interface TodayAnalyticsMetricLogicProps {
    shortId: string
}

export interface TodayAnalyticsMetricValue {
    value: number
    data: number[]
    labels: string[]
    trendsFilter: TrendsFilter | null
}

/** The number a trends insight shows, as its Metric display sums it up. Null for any other insight, or before its first result. */
export function metricFromInsight(insight: InsightApi): TodayAnalyticsMetricValue | null {
    const source = (insight.query as { source?: { kind?: string; trendsFilter?: TrendsFilter } } | null)?.source
    const series = Array.isArray(insight.result) ? (insight.result[0] as TrendResult | undefined) : undefined
    if (source?.kind !== 'TrendsQuery' || series?.count == null) {
        return null
    }
    const trendsFilter = source.trendsFilter ?? null
    return {
        value: computeMetricSummary(trendsFilter?.metricSummary ?? METRIC_SUMMARY_DEFAULT, series.count, series.data),
        data: series.data ?? [],
        labels: series.labels ?? [],
        trendsFilter,
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayAnalyticsMetricLogicValues {
    currentProjectId: number | string // teamLogic
    insight: InsightApi | null
    insightLoading: boolean
    loadFailed: boolean
    metric: TodayAnalyticsMetricValue | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayAnalyticsMetricLogicActions {
    loadInsight: () => void
    loadInsightFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadInsightSuccess: (
        insight: InsightApi | null,
        payload?: any
    ) => {
        insight: InsightApi | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayAnalyticsMetricLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        metric: (insight: InsightApi | null) => TodayAnalyticsMetricValue | null
    }
}

export type todayAnalyticsMetricLogicType = MakeLogicType<
    todayAnalyticsMetricLogicValues,
    todayAnalyticsMetricLogicActions,
    TodayAnalyticsMetricLogicProps,
    todayAnalyticsMetricLogicMeta
>

export const todayAnalyticsMetricLogic = kea<todayAnalyticsMetricLogicType>([
    props({} as TodayAnalyticsMetricLogicProps),
    key((props) => props.shortId),
    path((key) => ['layout', 'today', 'todayAnalyticsMetricLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentProjectId']] })),
    loaders(({ props, values }) => ({
        insight: [
            null as InsightApi | null,
            {
                // A sidebar must not start a query on every page load, so it reads the cached result. A stale or
                // missing result starts a background refresh, which the next load shows.
                loadInsight: async () => {
                    const { results } = await insightsList(String(values.currentProjectId), {
                        short_id: props.shortId,
                        refresh: 'async',
                    })
                    return results[0] ?? null
                },
            },
        ],
    })),
    reducers({
        loadFailed: [false, { loadInsight: () => false, loadInsightFailure: () => true }],
    }),
    selectors({
        metric: [(s) => [s.insight], (insight: InsightApi | null) => (insight ? metricFromInsight(insight) : null)],
    }),
    afterMount(({ actions }) => {
        actions.loadInsight()
    }),
])
