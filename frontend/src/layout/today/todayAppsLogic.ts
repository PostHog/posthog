import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'

import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { getProductAccessDisabledReason } from 'lib/utils/accessControlUtils'
import { urls } from 'scenes/urls'

import { PINNED_CATEGORY, getNavProductItems } from '~/layout/panel-layout/navbar/tabs/navProductItems'
import {
    ProductsItemGroup,
    groupProducts,
    productMatchesSearch,
} from '~/layout/panel-layout/navbar/tabs/productsCatalog'
import { FileSystemImport } from '~/queries/schema/schema-general'

import { todayRecentsLogic } from './todayRecentsLogic'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayAppsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    recentToolHrefs: string[] // todayRecentsLogic
    appGroups: ProductsItemGroup[]
    apps: FileSystemImport[]
    pinnedApps: FileSystemImport[]
    recentApps: FileSystemImport[]
    search: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayAppsLogicActions {
    setSearch: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayAppsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        apps: (featureFlags: FeatureFlagsSet) => FileSystemImport[]
        pinnedApps: (apps: FileSystemImport[], search: string) => FileSystemImport[]
        appGroups: (apps: FileSystemImport[], search: string) => ProductsItemGroup[]
        recentApps: (recentToolHrefs: string[], apps: FileSystemImport[], search: string) => FileSystemImport[]
    }
}

export type todayAppsLogicType = MakeLogicType<
    todayAppsLogicValues,
    todayAppsLogicActions,
    Record<string, any>,
    todayAppsLogicMeta
>

export const todayAppsLogic = kea<todayAppsLogicType>([
    path(['layout', 'today', 'todayAppsLogic']),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags'], todayRecentsLogic, ['recentToolHrefs']] })),
    actions({ setSearch: (search: string) => ({ search }) }),
    reducers({ search: ['', { setSearch: (_, { search }) => search }] }),
    selectors({
        apps: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): FileSystemImport[] =>
                // Home has its own rail item.
                getNavProductItems(featureFlags).filter(
                    (item) => item.href !== urls.projectRoot() && !getProductAccessDisabledReason(item)
                ),
        ],
        pinnedApps: [
            (s) => [s.apps, s.search],
            (apps: FileSystemImport[], search: string): FileSystemImport[] =>
                apps
                    .filter((item) => item.category === PINNED_CATEGORY && productMatchesSearch(item, search))
                    .sort((a, b) => (a.visualOrder ?? Infinity) - (b.visualOrder ?? Infinity)),
        ],
        appGroups: [
            (s) => [s.apps, s.search],
            (apps: FileSystemImport[], search: string): ProductsItemGroup[] =>
                groupProducts(
                    apps.filter((item) => item.category !== PINNED_CATEGORY),
                    search
                ),
        ],
        recentApps: [
            (s) => [s.recentToolHrefs, s.apps, s.search],
            (hrefs: string[], apps: FileSystemImport[], search: string): FileSystemImport[] =>
                hrefs
                    .flatMap((href) => apps.find((app) => app.href === href) ?? [])
                    .filter((app) => productMatchesSearch(app, search)),
        ],
    }),
])
