export const todayViewsLogic = kea<todayViewsLogicType>([
    path(['layout', 'today', 'todayViewsLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            userLogic,
            ['user'],
            todayRecentsLogic,
            ['recentViewEntries'],
            viewFeedLogic,
            ['sources', 'spaceNames'],
        ],
        actions: [viewFeedLogic, ['ensureFeed', 'refreshFeed', 'sourceRefreshed']],
    })),
    actions({
        loadRecentViews: true,
        loadMoreRecentViews: true,
        setRecentQuery: (query: string) => ({ query }),
        setRecentSearch: (search: string) => ({ search }),
        setRecentFilters: (filters: TodayViewsFilters) => ({ filters }),
        clearRecentSearchAndFilters: true,
        /** The open canvas reports whether its agent or a build is at work, which it knows exactly. Null when it closes. */
        setOpenCanvasBuilding: (canvasId: string, building: boolean | null) => ({ canvasId, building }),
    }),
    loaders(({ values }) => ({
        // A canvas on its first build has nothing to show until its first version, so until then its run
        // says whether the agent is building it. Later runs stay open after the agent's turn, so they cannot.
        firstBuilds: [
            {} as Record<string, FirstBuildState>,
            {
                loadFirstBuilds: async (_: void, breakpoint) => {
                    const projectId = values.currentTeamId ? String(values.currentTeamId) : null
                    const pending = values.allRecentViews.items.filter((item) => item.firstBuildTaskId)
                    if (!projectId || !pending.length) {
                        return {}
                    }
                    const results = await Promise.allSettled(
                        pending.map(async (item): Promise<[string, FirstBuildState]> => {
                            const [canvas, task] = await Promise.all([
                                canvasesRetrieve(projectId, item.id),
                                tasksRetrieve(projectId, item.firstBuildTaskId as string),
                            ])
                            return [
                                item.id,
                                { hasVersion: !!canvas.current_version_id, runStatus: task.latest_run?.status ?? null },
                            ]
                        })
                    )
                    breakpoint()
                    // A canvas whose lookup failed shows no spinner rather than holding up the rest.
                    return Object.fromEntries(
                        results.flatMap((result) => (result.status === 'fulfilled' ? [result.value] : []))
                    )
                },
            },
        ],
    })),
    reducers({
        recentQuery: ['', { setRecentQuery: (_, { query }) => query, clearRecentSearchAndFilters: () => '' }],
        recentSearch: ['', { setRecentSearch: (_, { search }) => search, clearRecentSearchAndFilters: () => '' }],
        recentFilters: [
            DEFAULT_VIEWS_FILTERS,
            { persist: true },
            {
                setRecentFilters: (_, { filters }) => filters,
                clearRecentSearchAndFilters: () => DEFAULT_VIEWS_FILTERS,
            },
        ],
        openCanvasBuilding: [
            {} as Record<string, boolean>,
            {
                setOpenCanvasBuilding: (state, { canvasId, building }) => {
                    const { [canvasId]: _, ...rest } = state
                    return building === null ? rest : { ...rest, [canvasId]: building }
                },
            },
        ],
    }),
    selectors({
        recentlyViewed: [
            (s) => [s.recentViewEntries, s.recentQuery],
            (recentViewEntries: TodayRecentEntry[], recentQuery: string): TodayRecentEntry[] =>
                recentViewEntries.filter((recent) => matchesPaneQuery(recent.name, recentQuery)),
        ],
        recentFiltersActive: [
            (s) => [s.recentFilters],
            (recentFilters: TodayViewsFilters): boolean => viewsFiltersActive(recentFilters),
        ],
        recentFeedQuery: [
            (s) => [s.recentFilters, s.recentSearch],
            (recentFilters: TodayViewsFilters, recentSearch: string): ViewFeedQuery => ({
                type: recentFilters.type,
                search: recentSearch.trim(),
            }),
        ],
        allRecentViews: [
            (s) => [s.sources, s.spaceNames, s.currentTeamId],
            (
                sources: Record<string, ViewSourceState>,
                spaceNames: Record<string, string>,
                currentTeamId: number | null
            ): ViewFeed => selectViewFeed(sources, spaceNames, currentTeamId, ALL_RECENT_QUERY),
        ],
        recentViews: [
            (s) => [s.sources, s.spaceNames, s.currentTeamId, s.recentFeedQuery],
            (
                sources: Record<string, ViewSourceState>,
                spaceNames: Record<string, string>,
                currentTeamId: number | null,
                recentFeedQuery: ViewFeedQuery
            ): ViewFeed => selectViewFeed(sources, spaceNames, currentTeamId, recentFeedQuery),
        ],
        recentViewsLoading: [(s) => [s.recentViews], (recentViews: ViewFeed): boolean => recentViews.loading],
        recentUnavailable: [(s) => [s.recentViews], (recentViews: ViewFeed): boolean => recentViews.loadFailed],
        recentReady: [
            (s) => [s.recentViews, s.allRecentViews],
            (recentViews: ViewFeed, allRecentViews: ViewFeed): boolean =>
                recentViews.initialized || allRecentViews.initialized,
        ],
        recentItems: [
            (s) => [s.recentViews, s.allRecentViews, s.recentFeedQuery, s.recentQuery, s.recentFilters, s.user],
            (
                recentViews: ViewFeed,
                allRecentViews: ViewFeed,
                recentFeedQuery: ViewFeedQuery,
                recentQuery: string,
                recentFilters: TodayViewsFilters,
                user: UserType | null
            ): ViewItem[] => {
                const userUuid = user?.uuid ?? null
                if (recentViews.initialized && recentQuery.trim() === recentFeedQuery.search) {
                    return filterRecentViews(recentViews.items, '', recentFilters, userUuid)
                }
                return filterRecentViews(allRecentViews.items, recentQuery, recentFilters, userUuid)
            },
        ],
        recentHasMore: [
            (s) => [s.recentViews, s.recentFeedQuery, s.recentQuery],
            (recentViews: ViewFeed, recentFeedQuery: ViewFeedQuery, recentQuery: string): boolean =>
                recentViews.initialized && recentViews.hasMore && recentQuery.trim() === recentFeedQuery.search,
        ],
        buildingViewIds: [
            (s) => [s.allRecentViews, s.firstBuilds, s.openCanvasBuilding],
            (
                allRecentViews: ViewFeed,
                firstBuilds: Record<string, FirstBuildState>,
                openCanvasBuilding: Record<string, boolean>
            ): string[] =>
                allRecentViews.items
                    .filter((item) => {
                        if (item.id in openCanvasBuilding) {
                            return openCanvasBuilding[item.id]
                        }
                        const firstBuild = firstBuilds[item.id]
                        return (
                            !!item.firstBuildTaskId &&
                            !!firstBuild &&
                            !firstBuild.hasVersion &&
                            !!firstBuild.runStatus &&
                            !TERMINAL_RUN_STATUSES.has(firstBuild.runStatus)
                        )
                    })
                    .map((item) => item.id),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadRecentViews: () => {
            actions.refreshFeed(ALL_RECENT_QUERY)
            if (values.recentFeedQuery.type !== 'all' || values.recentFeedQuery.search) {
                actions.refreshFeed(values.recentFeedQuery)
            }
        },
        sourceRefreshed: () => {
            if (values.allRecentViews.initialized && !values.allRecentViews.loading) {
                actions.loadFirstBuilds()
            }
        },
        setRecentQuery: async ({ query }, breakpoint) => {
            if (query.trim() !== values.recentSearch) {
                await breakpoint(query.trim() ? 200 : 0)
                actions.setRecentSearch(query.trim())
            }
        },
        loadMoreRecentViews: () => {
            if (values.recentHasMore) {
                actions.ensureFeed(values.recentFeedQuery, values.recentViews.items.length + VIEW_FEED_PAGE_SIZE)
            }
        },
        setRecentSearch: () => actions.ensureFeed(values.recentFeedQuery, VIEW_FEED_PAGE_SIZE),
        setRecentFilters: () => actions.ensureFeed(values.recentFeedQuery, VIEW_FEED_PAGE_SIZE),
        loadFirstBuildsSuccess: ({ firstBuilds }) => {
            const building = Object.values(firstBuilds).filter(
                (build) => !build.hasVersion && !!build.runStatus && !TERMINAL_RUN_STATUSES.has(build.runStatus)
            )
            // A first version changes the row, so the list reloads once the build is done.
            if (Object.values(firstBuilds).some((build) => build.hasVersion)) {
                actions.loadRecentViews()
                return
            }
            if (building.length && !values.allRecentViews.loading) {
                cache.disposables.add(() => {
                    const id = setTimeout(() => actions.loadFirstBuilds(), FIRST_BUILD_POLL_MS)
                    return () => clearTimeout(id)
                }, 'firstBuildPoll')
            } else {
                cache.disposables.dispose('firstBuildPoll')
            }
        },
        [router.actionTypes.locationChanged]: ({ pathname }: LocationChangedPayload) => {
            // Creating, restoring or opening a view lands on a new Views path, so the recents stay current.
            // Search and hash changes, such as dashboard filters, keep the path and do not reload.
            if (pathname !== cache.lastPathname && railPaneForPath(pathname) === 'views') {
                actions.loadRecentViews()
            }
            cache.lastPathname = pathname
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.lastPathname = router.values.location.pathname
        actions.loadRecentViews()
    }),
])
