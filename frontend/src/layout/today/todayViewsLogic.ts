import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import type { LocationChangedPayload } from 'kea-router/lib/types'

import { teamLogic } from 'scenes/teamLogic'
import { ViewItemsPage, fetchViewItems } from 'scenes/views/fetchViewItems'
import { ViewItem } from 'scenes/views/viewsUtils'

import { railPaneForPath } from './todayShellLogic'

// The sidebar shows the most recent views of every type in one list. The Views page lists the rest.
const RECENT_LIMIT = 12

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayViewsLogicValues {
    currentTeamId: number | null // teamLogic
    recentCollapsed: boolean
    recentItems: ViewItem[]
    recentUnavailable: boolean
    recentViews: ViewItemsPage | null
    recentViewsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayViewsLogicActions {
    loadRecentViews: (_: void) => void
    loadRecentViewsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRecentViewsSuccess: (
        recentViews: ViewItemsPage | null,
        payload?: void
    ) => {
        recentViews: ViewItemsPage | null
        payload?: void
    }
    toggleRecent: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayViewsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        recentItems: (recentViews: ViewItemsPage | null) => ViewItem[]
    }
    __keaTypeGenInternalReducerActions: {
        'location changed (kea.router)': ({
            method,
            pathname,
            search,
            searchParams,
            hash,
            hashParams,
            initial,
            url,
            routerState,
        }: LocationChangedPayload) => {
            payload: {
                hash: string
                hashParams: Record<string, any>
                initial: boolean
                method: 'POP' | 'PUSH' | 'REPLACE'
                pathname: string
                routerState: Record<string, any>
                search: string
                searchParams: Record<string, any>
                url: string
            }
            type: 'location changed (kea.router)'
        }
    }
}

export type todayViewsLogicType = MakeLogicType<
    todayViewsLogicValues,
    todayViewsLogicActions,
    Record<string, any>,
    todayViewsLogicMeta
>

export const todayViewsLogic = kea<todayViewsLogicType>([
    path(['layout', 'today', 'todayViewsLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        toggleRecent: true,
    }),
    loaders(({ values }) => ({
        recentViews: [
            null as ViewItemsPage | null,
            {
                loadRecentViews: async (_: void, breakpoint) => {
                    // Navigation reloads the list, so a burst of route changes costs one request.
                    await breakpoint(100)
                    if (!values.currentTeamId) {
                        return values.recentViews
                    }
                    const page = await fetchViewItems(String(values.currentTeamId), '')
                    breakpoint()
                    return page
                },
            },
        ],
    })),
    reducers({
        recentCollapsed: [false, { persist: true }, { toggleRecent: (state) => !state }],
        recentUnavailable: [false, { loadRecentViews: () => false, loadRecentViewsFailure: () => true }],
    }),
    selectors({
        recentItems: [
            (s) => [s.recentViews],
            // The items arrive newest first across every type.
            (recentViews: ViewItemsPage | null): ViewItem[] => (recentViews?.items ?? []).slice(0, RECENT_LIMIT),
        ],
    }),
    listeners(({ actions, cache }) => ({
        [router.actionTypes.locationChanged]: ({ pathname }: LocationChangedPayload) => {
            // Creating, restoring or opening a view lands on a new Views path, so the recents stay current.
            // Search and hash changes, such as dashboard filters, keep the path and do not reload.
            if (pathname !== cache.lastPathname && railPaneForPath(pathname) === 'views') {
                actions.loadRecentViews()
            }
            cache.lastPathname = pathname
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.lastPathname = router.values.location.pathname
        actions.loadRecentViews()
    }),
])
