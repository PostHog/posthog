export const todayViewsLogic = kea<todayViewsLogicType>([
    path(['layout', 'today', 'todayViewsLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId'], userLogic, ['user']] })),
    actions({
        receiveRecentViews: (page: ViewItemsPage) => ({ page }),
        toggleRecent: true,
        setRecentQuery: (query: string) => ({ query }),
        setRecentSearchOpen: (open: boolean) => ({ open }),
        setRecentFilters: (filters: TodayViewsFilters) => ({ filters }),
        clearRecentSearchAndFilters: true,
        /** The open canvas reports whether its agent or a build is at work, which it knows exactly. Null when it closes. */
        setOpenCanvasBuilding: (canvasId: string, building: boolean | null) => ({ canvasId, building }),
    }),
    loaders(({ values, actions }) => ({
        recentViews: [
            null as ViewItemsPage | null,
            {
                loadRecentViews: async (_: void, breakpoint) => {
                    // Navigation reloads the list, so a burst of route changes costs one request.
                    await breakpoint(100)
                    if (!values.currentTeamId) {
                        return values.recentViews
                    }
                    const teamId = values.currentTeamId
                    const page = await fetchViewItems(String(teamId), '', (page) => {
                        breakpoint()
                        if (values.currentTeamId === teamId) {
                            actions.receiveRecentViews(page)
                        }
                    })
                    breakpoint()
                    return values.currentTeamId === teamId ? page : values.recentViews
                },
            },
        ],
        // A canvas on its first build has nothing to show until its first version, so until then its run
        // says whether the agent is building it. Later runs stay open after the agent's turn, so they cannot.
        firstBuilds: [
            {} as Record<string, FirstBuildState>,
            {
                loadFirstBuilds: async (_: void, breakpoint) => {
                    const projectId = values.currentTeamId ? String(values.currentTeamId) : null
                    const pending = (values.recentViews?.items ?? []).filter((item) => item.firstBuildTaskId)
                    if (!projectId || !pending.length) {
                        return {}
                    }
                    const results = await Promise.allSettled(
                        pending.map(async (item): Promise<[string, FirstBuildState]> => {
                            const [canvas, task] = await Promise.all([
                                canvasesRetrieve(projectId, item.id),
                                tasksRetrieve(projectId, item.firstBuildTaskId as string),
                            ])
                            return [
                                item.id,
                                { hasVersion: !!canvas.current_version_id, runStatus: task.latest_run?.status ?? null },
                            ]
                        })
                    )
                    breakpoint()
                    // A canvas whose lookup failed shows no spinner rather than holding up the rest.
                    return Object.fromEntries(
                        results.flatMap((result) => (result.status === 'fulfilled' ? [result.value] : []))
                    )
                },
            },
        ],
    })),
    reducers({
        recentViews: {
            receiveRecentViews: (_, { page }) => page,
        },
        recentCollapsed: [false, { persist: true }, { toggleRecent: (state) => !state }],
        recentUnavailable: [false, { loadRecentViews: () => false, loadRecentViewsFailure: () => true }],
        recentQuery: ['', { setRecentQuery: (_, { query }) => query, clearRecentSearchAndFilters: () => '' }],
        recentSearchOpen: [
            false,
            { setRecentSearchOpen: (_, { open }) => open, clearRecentSearchAndFilters: () => false },
        ],
        recentFilters: [
            DEFAULT_VIEWS_FILTERS,
            { persist: true },
            {
                setRecentFilters: (_, { filters }) => filters,
                clearRecentSearchAndFilters: () => DEFAULT_VIEWS_FILTERS,
            },
        ],
        openCanvasBuilding: [
            {} as Record<string, boolean>,
            {
                setOpenCanvasBuilding: (state, { canvasId, building }) => {
                    const { [canvasId]: _, ...rest } = state
                    return building === null ? rest : { ...rest, [canvasId]: building }
                },
            },
        ],
    }),
    selectors({
        recentFiltersActive: [
            (s) => [s.recentFilters],
            (recentFilters: TodayViewsFilters): boolean => viewsFiltersActive(recentFilters),
        ],
        recentSearchVisible: [
            (s) => [s.recentSearchOpen, s.recentQuery],
            (recentSearchOpen: boolean, recentQuery: string): boolean => recentSearchOpen || recentQuery !== '',
        ],
        recentItems: [
            (s) => [s.recentViews, s.recentQuery, s.recentFilters, s.user],
            // The items arrive newest first across every type. A search or filter looks past the first few.
            (
                recentViews: ViewItemsPage | null,
                recentQuery: string,
                recentFilters: TodayViewsFilters,
                user: UserType | null
            ): ViewItem[] => {
                const items = recentViews?.items ?? []
                if (!recentQuery.trim() && !viewsFiltersActive(recentFilters)) {
                    return items.slice(0, RECENT_LIMIT)
                }
                return filterRecentViews(items, recentQuery, recentFilters, user?.uuid ?? null)
            },
        ],
        buildingViewIds: [
            (s) => [s.recentViews, s.firstBuilds, s.openCanvasBuilding],
            (
                recentViews: ViewItemsPage | null,
                firstBuilds: Record<string, FirstBuildState>,
                openCanvasBuilding: Record<string, boolean>
            ): string[] =>
                (recentViews?.items ?? [])
                    .filter((item) => {
                        if (item.id in openCanvasBuilding) {
                            return openCanvasBuilding[item.id]
                        }
                        const firstBuild = firstBuilds[item.id]
                        return (
                            !!item.firstBuildTaskId &&
                            !!firstBuild &&
                            !firstBuild.hasVersion &&
                            !!firstBuild.runStatus &&
                            !TERMINAL_RUN_STATUSES.has(firstBuild.runStatus)
                        )
                    })
                    .map((item) => item.id),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadRecentViewsSuccess: () => {
            actions.loadFirstBuilds()
        },
        loadFirstBuildsSuccess: ({ firstBuilds }) => {
            const building = Object.values(firstBuilds).filter(
                (build) => !build.hasVersion && !!build.runStatus && !TERMINAL_RUN_STATUSES.has(build.runStatus)
            )
            // A first version changes the row, so the list reloads once the build is done.
            if (Object.values(firstBuilds).some((build) => build.hasVersion)) {
                actions.loadRecentViews()
                return
            }
            if (building.length && !values.recentViewsLoading) {
                cache.disposables.add(() => {
                    const id = setTimeout(() => actions.loadFirstBuilds(), FIRST_BUILD_POLL_MS)
                    return () => clearTimeout(id)
                }, 'firstBuildPoll')
            } else {
                cache.disposables.dispose('firstBuildPoll')
            }
        },
        [router.actionTypes.locationChanged]: ({ pathname }: LocationChangedPayload) => {
            // Creating, restoring or opening a view lands on a new Views path, so the recents stay current.
            // Search and hash changes, such as dashboard filters, keep the path and do not reload.
            if (pathname !== cache.lastPathname && railPaneForPath(pathname) === 'views') {
                actions.loadRecentViews()
            }
            cache.lastPathname = pathname
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.lastPathname = router.values.location.pathname
        actions.loadRecentViews()
    }),
])
