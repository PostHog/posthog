/** The org switcher: the orgs and pending invites the search matches, and the org actions after them. */
export const todayOrgMenuLogic = kea<todayOrgMenuLogicType>([
    path(['layout', 'today', 'todayOrgMenuLogic']),
    connect(() => ({
        values: [
            organizationLogic,
            ['currentOrganization'],
            userLogic,
            ['otherOrganizations', 'isSwitchingOrganization'],
            pendingInvitesLogic,
            ['pendingInvites'],
            preflightLogic,
            ['preflight', 'isCloudOrDev'],
            billingLogic,
            ['billingEntryUrl'],
            upgradeModalLogic,
            ['guardAvailableFeature'],
        ],
        actions: [
            newAccountMenuLogic,
            ['openOrgSwitcher', 'closeOrgSwitcher'],
            userLogic,
            ['updateCurrentOrganization'],
            globalModalsLogic,
            ['showCreateOrganizationModal'],
            inviteLogic,
            ['showInviteModal'],
            eventUsageLogic,
            ['reportInviteMembersButtonClicked'],
        ],
    })),
    actions({
        setOrgSearchValue: (searchValue: string) => ({ searchValue }),
        switchOrganization: (organizationId: string) => ({ organizationId }),
        openInvite: (inviteId: string) => ({ inviteId }),
        runOrgMenuAction: (key: OrgMenuActionKey) => ({ key }),
    }),
    reducers({
        orgSearchValue: [
            '',
            {
                setOrgSearchValue: (_, { searchValue }) => searchValue,
                openOrgSwitcher: () => '',
                closeOrgSwitcher: () => '',
            },
        ],
    }),
    selectors({
        organizations: [
            (s) => [s.currentOrganization, s.otherOrganizations, s.orgSearchValue],
            (
                currentOrganization: OrganizationType | null,
                otherOrganizations: OrganizationBasicType[],
                orgSearchValue: string
            ): OrganizationBasicType[] =>
                [...(currentOrganization ? [currentOrganization] : []), ...otherOrganizations]
                    .filter((organization) => matchesSwitcherSearch(organization.name, orgSearchValue))
                    .sort((a, b) => a.name.localeCompare(b.name)),
        ],
        invites: [
            (s) => [s.pendingInvites, s.orgSearchValue],
            (pendingInvites: PendingInviteForCurrentUser[], orgSearchValue: string): PendingInviteForCurrentUser[] =>
                pendingInvites.filter((invite) => matchesSwitcherSearch(invite.organization_name, orgSearchValue)),
        ],
        orgMenuActions: [
            (s) => [s.isCloudOrDev, s.billingEntryUrl, s.preflight],
            (
                isCloudOrDev: boolean | undefined,
                billingEntryUrl: string | null,
                preflight: PreflightStatus | null
            ): OrgMenuActionKey[] => [
                'invite-members',
                ...(isCloudOrDev && billingEntryUrl ? ['billing' as const] : []),
                'org-settings',
                ...(preflight?.can_create_org ? ['new-org' as const] : []),
            ],
        ],
    }),
    listeners(({ actions, values }) => ({
        switchOrganization: ({ organizationId }) => {
            // A switch reloads the page when it succeeds. Until then, a second pick would race the first.
            if (organizationId === values.currentOrganization?.id || values.isSwitchingOrganization) {
                return
            }
            actions.closeOrgSwitcher()
            actions.updateCurrentOrganization(organizationId)
        },
        openInvite: ({ inviteId }) => {
            window.location.href = urls.inviteSignup(inviteId)
        },
        runOrgMenuAction: ({ key }) => {
            actions.closeOrgSwitcher()
            if (key === 'invite-members') {
                actions.showInviteModal()
                actions.reportInviteMembersButtonClicked()
            } else if (key === 'billing' && values.billingEntryUrl) {
                router.actions.push(values.billingEntryUrl)
            } else if (key === 'org-settings') {
                router.actions.push(urls.settings('organization'))
            } else if (key === 'new-org') {
                values.guardAvailableFeature(
                    AvailableFeature.ORGANIZATIONS_PROJECTS,
                    () => actions.showCreateOrganizationModal(),
                    { guardOnCloud: false }
                )
            }
        },
    })),
])
