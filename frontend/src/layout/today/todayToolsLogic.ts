import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'

import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { getProductAccessDisabledReason } from 'lib/utils/accessControlUtils'
import { TOOL_FILE_SYSTEM_TYPES } from 'scenes/library/libraryLogic'

import { fileSystemTypes, getTreeItemsMetadata, getTreeItemsProducts } from '~/products'
import { FileSystemImport } from '~/queries/schema/schema-general'

export interface ToolGroup {
    category: string
    tools: FileSystemImport[]
}

// Workspaces for building queries and writing things up come first, apart from the product pages.
const PINNED_TOOL_ICONS = ['sql_editor', 'notebook']
export const PINNED_TOOLS_CATEGORY = 'Workspace'

export function toolLabel(tool: FileSystemImport): string {
    return tool.displayLabel || tool.path
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayToolsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    search: string
    toolGroups: ToolGroup[]
    tools: FileSystemImport[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayToolsLogicActions {
    setSearch: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayToolsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        tools: (featureFlags: FeatureFlagsSet) => FileSystemImport[]
        toolGroups: (tools: FileSystemImport[], search: string) => ToolGroup[]
    }
}

export type todayToolsLogicType = MakeLogicType<
    todayToolsLogicValues,
    todayToolsLogicActions,
    Record<string, any>,
    todayToolsLogicMeta
>

export const todayToolsLogic = kea<todayToolsLogicType>([
    path(['layout', 'today', 'todayToolsLogic']),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags']] })),
    actions({ setSearch: (search: string) => ({ search }) }),
    reducers({ search: ['', { setSearch: (_, { search }) => search }] }),
    selectors({
        tools: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): FileSystemImport[] => {
                const seen = new Set<string>()
                return [...getTreeItemsProducts(), ...getTreeItemsMetadata()]
                    .filter((item) => {
                        const type = item.type?.split('/')[0] || item.iconType || ''
                        if (
                            !item.href ||
                            seen.has(item.href) ||
                            // Saved object types live in Library, except the ones that are working pages.
                            (type in fileSystemTypes && !TOOL_FILE_SYSTEM_TYPES.has(type)) ||
                            (item.flag && !featureFlags[item.flag as keyof FeatureFlagsSet]) ||
                            getProductAccessDisabledReason(item)
                        ) {
                            return false
                        }
                        seen.add(item.href)
                        return true
                    })
                    .sort((first, second) => toolLabel(first).localeCompare(toolLabel(second)))
            },
        ],
        toolGroups: [
            (s) => [s.tools, s.search],
            (tools: FileSystemImport[], search: string): ToolGroup[] => {
                const query = search.trim().toLowerCase()
                const groups = new Map<string, FileSystemImport[]>()
                for (const tool of tools) {
                    const pinned = PINNED_TOOL_ICONS.includes(tool.iconType ?? '')
                    const category = pinned ? PINNED_TOOLS_CATEGORY : tool.category || 'Other'
                    if (query && !`${toolLabel(tool)} ${category}`.toLowerCase().includes(query)) {
                        continue
                    }
                    groups.set(category, [...(groups.get(category) ?? []), tool])
                }
                return [...groups.entries()]
                    .map(([category, groupTools]) => ({ category, tools: groupTools }))
                    .sort(
                        (first, second) =>
                            Number(second.category === PINNED_TOOLS_CATEGORY) -
                                Number(first.category === PINNED_TOOLS_CATEGORY) ||
                            first.category.localeCompare(second.category)
                    )
            },
        ],
    }),
])
