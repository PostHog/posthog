import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'

import { libraryLogic } from 'scenes/library/libraryLogic'
import { LibraryObjectType } from 'scenes/library/libraryUtils'
import { toolsLogic } from 'scenes/tools/toolsLogic'
import { groupTools } from 'scenes/tools/toolsUtils'

import { FileSystemImport } from '~/queries/schema/schema-general'

import { matchesPaneQuery } from './todayPaneSearch'
import { TODAY_RECENTS_LIMIT, newestByName } from './todayRecentOrder'
import { TodayProductRow, productPageRow, recentProductRow } from './todayRecentProducts'
import { todayRecentProductsLogic } from './todayRecentProductsLogic'
import { railPaneForPath } from './todayShellLogic'

export interface TodayProductSection {
    key: string
    label: string
    rows: TodayProductRow[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayToolsLogicValues {
    objectTypes: LibraryObjectType[] // libraryLogic
    recentProductKeys: string[] // todayRecentProductsLogic
    productPages: FileSystemImport[] // toolsLogic
    tools: FileSystemImport[] // toolsLogic
    productSections: TodayProductSection[]
    productTools: FileSystemImport[]
    recentProducts: TodayProductRow[]
    search: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayToolsLogicActions {
    setSearch: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayToolsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        productTools: (tools: FileSystemImport[]) => FileSystemImport[]
        productSections: (productTools: FileSystemImport[], search: string) => TodayProductSection[]
        recentProducts: (
            recentProductKeys: string[],
            productPages: FileSystemImport[],
            objectTypes: LibraryObjectType[],
            search: string
        ) => TodayProductRow[]
    }
}

export type todayToolsLogicType = MakeLogicType<
    todayToolsLogicValues,
    todayToolsLogicActions,
    Record<string, any>,
    todayToolsLogicMeta
>

export const todayToolsLogic = kea<todayToolsLogicType>([
    path(['layout', 'today', 'todayToolsLogic']),
    connect(() => ({
        values: [
            toolsLogic,
            ['tools', 'productPages'],
            todayRecentProductsLogic,
            ['recentProductKeys'],
            libraryLogic,
            ['objectTypes'],
        ],
    })),
    actions({ setSearch: (search: string) => ({ search }) }),
    reducers({ search: ['', { setSearch: (_, { search }) => search }] }),
    selectors({
        // Tools whose pages open another pane, like dashboards and notebooks under Views, stay out of Products.
        productTools: [
            (s) => [s.tools],
            (tools: FileSystemImport[]): FileSystemImport[] =>
                tools.filter((tool) => !tool.href || railPaneForPath(tool.href.split('?')[0]) !== 'views'),
        ],
        productSections: [
            (s) => [s.productTools, s.search],
            (tools: FileSystemImport[], search: string): TodayProductSection[] =>
                groupTools(tools, search).map((group) => ({
                    key: group.category,
                    label: group.category,
                    rows: group.tools.map(productPageRow),
                })),
        ],
        recentProducts: [
            (s) => [s.recentProductKeys, s.productPages, s.objectTypes, s.search],
            (
                keys: string[],
                productPages: FileSystemImport[],
                objectTypes: LibraryObjectType[],
                search: string
            ): TodayProductRow[] =>
                newestByName(
                    keys.flatMap((key) => {
                        const row = recentProductRow(key, productPages, objectTypes)
                        return row && matchesPaneQuery(row.searchText, search) ? [row] : []
                    }),
                    (row) => row.label,
                    (row) => row.key,
                    TODAY_RECENTS_LIMIT
                ),
        ],
    }),
])
