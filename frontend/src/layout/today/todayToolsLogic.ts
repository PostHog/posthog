/** Groups the tools like the Products tab of the current navigation: Popular first, then the same categories. */
export function groupTodayProducts(tools: FileSystemImport[], search: string): ToolGroup[] {
    const matching = tools
        .filter((tool) => toolMatchesSearch(tool, search))
        .map((tool) => (POPULAR_PRODUCT_PATHS.includes(tool.path) ? { ...tool, category: POPULAR_CATEGORY } : tool))
    return groupProducts(matching, '').map((group) => ({ category: group.label, tools: group.items }))
}

/** The products behind the product stars, in saved order. A star made before a rename still finds its product by href. */
export function starredProducts(shortcuts: FileSystemEntry[], candidates: FileSystemImport[]): FileSystemImport[] {
    const seen = new Set<string>()
    return shortcuts.flatMap((shortcut) => {
        const item = candidates.find((candidate) => !!candidate.href && findProductShortcut(candidate, [shortcut]))
        if (!item?.href || seen.has(item.href)) {
            return []
        }
        seen.add(item.href)
        return [item]
    })
}

export const todayToolsLogic = kea<todayToolsLogicType>([
    path(['layout', 'today', 'todayToolsLogic']),
    connect(() => ({
        values: [
            toolsLogic,
            ['tools'],
            todayRecentsLogic,
            ['recentToolHrefs'],
            projectTreeDataLogic,
            ['shortcutData', 'shortcutDataLoading'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [projectTreeDataLogic, ['addShortcutItem', 'deleteShortcut']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        toggleStarred: (item: FileSystemImport) => ({ item }),
    }),
    reducers({ search: ['', { setSearch: (_, { search }) => search }] }),
    selectors({
        // Tools whose pages open another pane, like dashboards and notebooks under Analytics, stay out of Products.
        productTools: [
            (s) => [s.tools],
            (tools: FileSystemImport[]): FileSystemImport[] =>
                tools.filter((tool) => !tool.href || railPaneForPath(tool.href.split('?')[0]) !== 'analytics'),
        ],
        toolGroups: [
            (s) => [s.productTools, s.search],
            (tools: FileSystemImport[], search: string): ToolGroup[] => groupTodayProducts(tools, search),
        ],
        recentTools: [
            (s) => [s.recentToolHrefs, s.productTools, s.search],
            (hrefs: string[], tools: FileSystemImport[], search: string): FileSystemImport[] =>
                hrefs
                    .flatMap((href) => tools.find((tool) => tool.href === href) ?? [])
                    .filter((tool) => toolMatchesSearch(tool, search)),
        ],
        // Products that open a Library list or the Views pane count too, so a star made in the current navigation shows here.
        starredTools: [
            (s) => [s.shortcutData, s.tools, s.featureFlags, s.search],
            (
                shortcuts: FileSystemEntry[],
                tools: FileSystemImport[],
                featureFlags: FeatureFlagsSet,
                search: string
            ): FileSystemImport[] => {
                const candidates = [...tools, ...getToolSourceItems()].filter(
                    (item) => isFileSystemImportFlagEnabled(item, featureFlags) && !getProductAccessDisabledReason(item)
                )
                return starredProducts(shortcuts, candidates).filter((item) => toolMatchesSearch(item, search))
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        toggleStarred: ({ item }) => {
            // The star buttons are disabled while a change saves. This also stops a repeated dispatch.
            if (values.shortcutDataLoading) {
                return
            }
            const shortcut = findProductShortcut(item, values.shortcutData)
            if (shortcut?.id) {
                actions.deleteShortcut(shortcut.id)
            } else {
                actions.addShortcutItem(item as FileSystemEntry)
            }
        },
    })),
])
