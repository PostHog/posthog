import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { router } from 'kea-router'
import type { LocationChangedPayload } from 'kea-router/lib/types'

import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { toolsLogic } from 'scenes/tools/toolsLogic'

import type { FileSystemImport } from '../../queries/schema/schema-general'
import { TODAY_RECENTS_LIMIT } from './todayRecentOrder'
import { pickRecentKey, recentKeyForPath, touchRecentKey } from './todayRecentProducts'
import { railPaneForPath } from './todayShellLogic'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentProductsLogicValues {
    productPages: FileSystemImport[] // toolsLogic
    recentProductKeys: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentProductsLogicActions {
    pickProduct: (key: string) => {
        key: string
    }
    touchProduct: (key: string) => {
        key: string
    }
    visitPage: (pathname: string) => {
        pathname: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentProductsLogicMeta {
    __keaTypeGenInternalReducerActions: {
        'location changed (kea.router)': ({
            method,
            pathname,
            search,
            searchParams,
            hash,
            hashParams,
            initial,
            url,
            routerState,
        }: LocationChangedPayload) => {
            payload: {
                hash: string
                hashParams: Record<string, any>
                initial: boolean
                method: 'POP' | 'PUSH' | 'REPLACE'
                pathname: string
                routerState: Record<string, any>
                search: string
                searchParams: Record<string, any>
                url: string
            }
            type: 'location changed (kea.router)'
        }
    }
}

export type todayRecentProductsLogicType = MakeLogicType<
    todayRecentProductsLogicValues,
    todayRecentProductsLogicActions,
    Record<string, any>,
    todayRecentProductsLogicMeta
>

/** The Products pane's recently viewed list. Products have no server record of views, so this browser keeps one. */
export const todayRecentProductsLogic = kea<todayRecentProductsLogicType>([
    path(['layout', 'today', 'todayRecentProductsLogic']),
    connect(() => ({ values: [toolsLogic, ['productPages']] })),
    actions({
        visitPage: (pathname: string) => ({ pathname }),
        /** A row click names the product, since two rows can open one page, such as Worksheets and Business intelligence. */
        pickProduct: (key: string) => ({ key }),
        touchProduct: (key: string) => ({ key }),
    }),
    reducers({
        recentProductKeys: [
            [] as string[],
            // pinned: the storage key predates this logic. Changing it clears everyone's recents.
            { persist: true, storageKey: 'layout.today.todayRecentsLogic.recentToolHrefs' },
            {
                pickProduct: (state, { key }) => pickRecentKey(state, key, TODAY_RECENTS_LIMIT),
                touchProduct: (state, { key }) => touchRecentKey(state, key, TODAY_RECENTS_LIMIT),
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        visitPage: ({ pathname }) => {
            const path = removeProjectIdIfPresent(pathname)
            // Views list dashboards and notebooks on their own, and a slot they took would push a product out.
            const key = railPaneForPath(path) === 'views' ? null : recentKeyForPath(path, values.productPages)
            if (key) {
                actions.touchProduct(key)
            }
        },
        [router.actionTypes.locationChanged]: ({ pathname }: LocationChangedPayload) => {
            actions.visitPage(pathname)
        },
    })),
    afterMount(({ actions }) => {
        actions.visitPage(router.values.location.pathname)
    }),
])
