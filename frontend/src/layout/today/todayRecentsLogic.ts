import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'
import type { LocationChangedPayload } from 'kea-router/lib/types'

import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { VIEW_FILE_SYSTEM_TYPES, baseObjectType, libraryObjectHref } from 'scenes/library/libraryUtils'
import { toolHrefForPath } from 'scenes/tools/toolsUtils'

import { splitPath, unescapePath } from '~/layout/panel-layout/ProjectTree/utils'
import { recentItemsModel } from '~/models/recentItemsModel'
import { FileSystemEntry } from '~/queries/schema/schema-general'

export const TODAY_RECENTS_LIMIT = 5

export interface TodayRecentEntry {
    entry: FileSystemEntry
    name: string
    href: string
}

function pushRecent(list: string[], value: string): string[] {
    return [value, ...list.filter((item) => item !== value)].slice(0, TODAY_RECENTS_LIMIT)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentsLogicValues {
    recents: FileSystemEntry[] // recentItemsModel
    recentSessionIds: string[]
    recentToolHrefs: string[]
    recentViewEntries: TodayRecentEntry[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentsLogicActions {
    recordLocation: (
        pathname: string,
        searchParams: Record<string, any>
    ) => {
        pathname: string
        searchParams: Record<string, any>
    }
    recordSessionVisit: (sessionId: string) => {
        sessionId: string
    }
    recordToolVisit: (href: string) => {
        href: string
    }
}

