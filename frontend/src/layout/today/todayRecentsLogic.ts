export type todayRecentsLogicType = MakeLogicType<
    todayRecentsLogicValues,
    todayRecentsLogicActions,
    Record<string, any>,
    todayRecentsLogicMeta
>

/**
 * What the sidebar panes list as recently viewed. Views reads the project's recently viewed objects.
 * Tools and sessions have no server record of views, so this browser keeps one as the user moves between pages.
 */
export const todayRecentsLogic = kea<todayRecentsLogicType>([
    path(['layout', 'today', 'todayRecentsLogic']),
    connect(() => ({ values: [recentItemsModel, ['recents']] })),
    actions({
        recordToolVisit: (href: string) => ({ href }),
        recordSessionVisit: (sessionId: string) => ({ sessionId }),
        recordLocation: (pathname: string, searchParams: Record<string, any>) => ({ pathname, searchParams }),
    }),
    reducers({
        // pinned: storage keys for persisted state. Renaming them clears everyone's recents.
        recentToolHrefs: [
            [] as string[],
            { persist: true },
            { recordToolVisit: (state, { href }) => pushRecent(state, href) },
        ],
        recentSessionIds: [
            [] as string[],
            { persist: true },
            { recordSessionVisit: (state, { sessionId }) => pushRecent(state, sessionId) },
        ],
    }),
    selectors({
        recentViewEntries: [
            (s) => [s.recents],
            (recents: FileSystemEntry[]): TodayRecentEntry[] =>
                recents
                    .flatMap((entry) => {
                        const href = VIEW_FILE_SYSTEM_TYPES.has(baseObjectType(entry.type))
                            ? libraryObjectHref(entry)
                            : null
                        return href
                            ? [{ entry, href, name: unescapePath(splitPath(entry.path).pop() ?? entry.path) }]
                            : []
                    })
                    .slice(0, TODAY_RECENTS_LIMIT),
        ],
    }),
    listeners(({ actions }) => ({
        recordLocation: ({ pathname, searchParams }) => {
            const path = removeProjectIdIfPresent(pathname)
            const toolHref = toolHrefForPath(path)
            if (toolHref) {
                actions.recordToolVisit(toolHref)
            }
            if (path === '/ai' && typeof searchParams.task === 'string') {
                actions.recordSessionVisit(searchParams.task)
            }
        },
        [router.actionTypes.locationChanged]: ({ pathname, searchParams }: LocationChangedPayload) => {
            actions.recordLocation(pathname, searchParams)
        },
    })),
    afterMount(({ actions }) => {
        const { location, searchParams } = router.values
        actions.recordLocation(location.pathname, searchParams)
    }),
])
