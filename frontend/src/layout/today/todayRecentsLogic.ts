/** Mounted with the shell, so a record opened from any pane counts. */
export const todayRecentsLogic = kea<todayRecentsLogicType>([
    path(['layout', 'today', 'todayRecentsLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
        logic: [sceneLogic],
    })),
    actions({
        addRecent: (recent: TodayRecent) => ({ recent }),
        moveRecent: (pane: TodaySortableRecentPane, href: string, overHref: string) => ({ pane, href, overHref }),
        setRecentOrder: (pane: TodaySortableRecentPane, hrefs: string[]) => ({ pane, hrefs }),
    }),
    reducers({
        peopleRecents: [
            [] as TodayPeopleRecent[],
            // pinned: storage key of the saved People Recents, kept from the logic that held them before. Changing it
            // empties everyone's People Recents.
            { ...TODAY_USER_PERSIST_OPTIONS, storageKey: 'layout.today.todayPeopleRecentsLogic.recents' },
            {
                addRecent: (state, { recent }) => (isPeopleRecent(recent) ? addTodayRecent(state, recent) : state),
            },
        ],
        // pinned: storage key for the saved Monitor Recents. Renaming it empties everyone's Monitor Recents.
        monitorRecents: [
            [] as TodayMonitorRecent[],
            TODAY_USER_PERSIST_OPTIONS,
            {
                addRecent: (state, { recent }) =>
                    recent.type !== 'release' && !isPeopleRecent(recent) ? addTodayRecent(state, recent) : state,
            },
        ],
        // The hrefs of each pane's Recents, in the order a person dragged them into.
        recentOrder: [
            { people: [], monitor: [] } as Record<TodaySortableRecentPane, string[]>,
            TODAY_USER_PERSIST_OPTIONS,
            {
                setRecentOrder: (state, { pane, hrefs }) => ({ ...state, [pane]: hrefs }),
            },
        ],
        releaseRecents: [
            [] as StoredReleaseRecent[],
            TODAY_USER_PERSIST_OPTIONS,
            {
                addRecent: (state, { recent }) => {
                    if (recent.type !== 'release') {
                        return state
                    }
                    const updated = { ...recent, viewedAt: Date.now() }
                    return state[0]?.href === recent.href && state[0].name === recent.name
                        ? [updated, ...state.slice(1)]
                        : addTodayRecent(state, updated)
                },
            },
        ],
    }),
    selectors({
        // Similar to "breadcrumbs" in breadcrumbsLogic: the selector of whichever scene logic is active.
        currentRecent: [
            (s) => [
                s.featureFlags,
                (state, props): TodayRecent | null => {
                    const activeSceneLogic = sceneLogic.selectors.activeSceneLogic(state, props)
                    if (!activeSceneLogic || !(TODAY_RECENT_KEY in activeSceneLogic.selectors)) {
                        return null
                    }
                    const activeLoadedScene = sceneLogic.selectors.activeLoadedScene(state, props)
                    try {
                        return activeSceneLogic.selectors[TODAY_RECENT_KEY](
                            state,
                            activeLoadedScene?.paramsToProps?.(activeLoadedScene?.sceneParams) || props
                        )
                    } catch {
                        // The scene logic may not be mounted yet.
                        return null
                    }
                },
            ],
            (featureFlags: FeatureFlagsSet, recent: TodayRecent | null): TodayRecent | null =>
                recent &&
                featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV] &&
                isTodayPaneEnabled(recentPane(recent), featureFlags)
                    ? recent
                    : null,
            { resultEqualityCheck: objectsEqual },
        ],
        peopleRecentRows: [
            (s) => [s.peopleRecents, s.recentOrder],
            (recents: TodayPeopleRecent[], recentOrder: Record<TodaySortableRecentPane, string[]>) =>
                applySavedOrder(rowsByName(recents), recentOrder.people, (recent) => recent.href),
        ],
        monitorRecentRows: [
            (s) => [s.monitorRecents, s.recentOrder],
            (recents: TodayMonitorRecent[], recentOrder: Record<TodaySortableRecentPane, string[]>) =>
                applySavedOrder(rowsByName(recents), recentOrder.monitor, (recent) => recent.href),
        ],
    }),
    listeners(({ actions, values }) => ({
        moveRecent: ({ pane, href, overHref }) => {
            // A pane shows only some of its recents, so the move happens in the full list to keep the others in place.
            const rows = pane === 'people' ? values.peopleRecentRows : values.monitorRecentRows
            const hrefs = movedKeys(
                rows.map((recent) => recent.href),
                href,
                overHref
            )
            if (!hrefs) {
                return
            }
            actions.setRecentOrder(pane, hrefs)
            posthog.capture('today recent reordered', { pane })
        },
    })),
    subscriptions(({ actions }) => ({
        currentRecent: (recent: TodayRecent | null) => {
            if (recent) {
                actions.addRecent(recent)
            }
        },
    })),
])
