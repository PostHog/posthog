import { applySavedOrder, movedKeys } from './todaySavedOrder'
import { TODAY_USER_PERSIST_OPTIONS } from './todayUserPersistOptions'

function rowsByName<T extends TodayRecent>(recents: T[]): T[] {
    return newestByName(
        recents,
        (item) => item.name,
        (item) => item.href,
        TODAY_RECENTS_LIMIT
    )
}

