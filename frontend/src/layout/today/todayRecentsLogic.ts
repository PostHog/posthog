import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'
import { subscriptions } from 'kea-subscriptions'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { objectsEqual } from 'lib/utils/objects'
import { sceneLogic } from 'scenes/sceneLogic'

import { TodayMonitorRecent } from './todayMonitor'
import { newestByName } from './todayNewestByName'
import { isTodayPaneEnabled } from './todayPaneFlags'
import { TodayPeopleRecent } from './todayPeople'
import {
    TODAY_RECENTS_LIMIT,
    TODAY_RECENT_KEY,
    TodayRecent,
    addTodayRecent,
    isPeopleRecent,
    recentPane,
} from './todayRecents'
import { TODAY_USER_PERSIST_OPTIONS } from './todayUserPersistOptions'

function rowsByName<T extends TodayRecent>(recents: T[]): T[] {
    return newestByName(
        recents,
        (item) => item.name,
        (item) => item.href,
        TODAY_RECENTS_LIMIT
    )
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentRecent: TodayRecent | null
    monitorRecentRows: TodayMonitorRecent[]
    monitorRecents: TodayMonitorRecent[]
    peopleRecentRows: TodayPeopleRecent[]
    peopleRecents: TodayPeopleRecent[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentsLogicActions {
    addRecent: (recent: TodayRecent) => {
        recent: TodayRecent
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRecentsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        currentRecent: (featureFlags: FeatureFlagsSet, arg: TodayRecent | null) => TodayRecent | null
        peopleRecentRows: (peopleRecents: TodayPeopleRecent[]) => TodayPeopleRecent[]
        monitorRecentRows: (monitorRecents: TodayMonitorRecent[]) => TodayMonitorRecent[]
    }
}

export type todayRecentsLogicType = MakeLogicType<
    todayRecentsLogicValues,
    todayRecentsLogicActions,
    Record<string, any>,
    todayRecentsLogicMeta
>

/** Mounted with the shell, so a record opened from any pane counts. */
export const todayRecentsLogic = kea<todayRecentsLogicType>([
    path(['layout', 'today', 'todayRecentsLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
        logic: [sceneLogic],
    })),
    actions({
        addRecent: (recent: TodayRecent) => ({ recent }),
    }),
    reducers({
        peopleRecents: [
            [] as TodayPeopleRecent[],
            // pinned: storage key of the saved People Recents, kept from the logic that held them before. Changing it
            // empties everyone's People Recents.
            { ...TODAY_USER_PERSIST_OPTIONS, storageKey: 'layout.today.todayPeopleRecentsLogic.recents' },
            {
                addRecent: (state, { recent }) => (isPeopleRecent(recent) ? addTodayRecent(state, recent) : state),
            },
        ],
        // pinned: storage key for the saved Monitor Recents. Renaming it empties everyone's Monitor Recents.
        monitorRecents: [
            [] as TodayMonitorRecent[],
            TODAY_USER_PERSIST_OPTIONS,
            {
                addRecent: (state, { recent }) => (isPeopleRecent(recent) ? state : addTodayRecent(state, recent)),
            },
        ],
    }),
    selectors({
        // Similar to "breadcrumbs" in breadcrumbsLogic: the selector of whichever scene logic is active.
        currentRecent: [
            (s) => [
                s.featureFlags,
                (state, props): TodayRecent | null => {
                    const activeSceneLogic = sceneLogic.selectors.activeSceneLogic(state, props)
                    if (!activeSceneLogic || !(TODAY_RECENT_KEY in activeSceneLogic.selectors)) {
                        return null
                    }
                    const activeLoadedScene = sceneLogic.selectors.activeLoadedScene(state, props)
                    try {
                        return activeSceneLogic.selectors[TODAY_RECENT_KEY](
                            state,
                            activeLoadedScene?.paramsToProps?.(activeLoadedScene?.sceneParams) || props
                        )
                    } catch {
                        // The scene logic may not be mounted yet.
                        return null
                    }
                },
            ],
            (featureFlags: FeatureFlagsSet, recent: TodayRecent | null): TodayRecent | null =>
                recent &&
                featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV] &&
                isTodayPaneEnabled(recentPane(recent), featureFlags)
                    ? recent
                    : null,
            { resultEqualityCheck: objectsEqual },
        ],
        peopleRecentRows: [(s) => [s.peopleRecents], (recents: TodayPeopleRecent[]) => rowsByName(recents)],
        monitorRecentRows: [(s) => [s.monitorRecents], (recents: TodayMonitorRecent[]) => rowsByName(recents)],
    }),
    subscriptions(({ actions }) => ({
        currentRecent: (recent: TodayRecent | null) => {
            if (recent) {
                actions.addRecent(recent)
            }
        },
    })),
])
