import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { subscriptions } from 'kea-subscriptions'
import posthog from 'posthog-js'

import { navSwitchLogic } from 'lib/components/NavSwitch/navSwitchLogic'

import { todayRailLayoutLogic } from './todayRailLayoutLogic'
import { todaySeenLogic } from './todaySeenLogic'
import type { TodayRailPane } from './todayShellLogic'
import type { TodayTourPoint } from './todayTourGeometry'

// pinned: key in the user's server-side `has_seen_product_intro_for`. Renaming it shows the card again to everyone.
const DESIGN_CHANGELOG_KEY = 'today_rail_customize'
// The pane the changelog is about: it left the rail by default.
const CHATS_PANE: TodayRailPane = 'spaces'

/** A run of the "Show me" demo: where its cursor starts, and whether it first explains that Chats is hidden. */
export interface TodayCustomizeDemo {
    origin: TodayTourPoint
    explainChats: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayDesignChangelogLogicValues {
    newNavDialogOpen: boolean // navSwitchLogic
    arrangedPanes: TodayRailPane[] // todayRailLayoutLogic
    railHidden: TodayRailPane[] // todayRailLayoutLogic
    isSeen: (key: string) => boolean // todaySeenLogic
    changelogShown: boolean
    customizeHint: boolean
    demo: TodayCustomizeDemo | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayDesignChangelogLogicActions {
    setCustomizeOpen: (open: boolean) => {
        open: boolean
    } // todayRailLayoutLogic
    markSeen: (key: string) => {
        key: string
    } // todaySeenLogic
    markUnseen: (key: string) => {
        key: string
    } // todaySeenLogic
    dismissChangelog: () => {
        value: true
    }
    endDemo: () => {
        value: true
    }
    setCustomizeHint: (shown: boolean) => {
        shown: boolean
    }
    setDemo: (demo: TodayCustomizeDemo) => {
        demo: TodayCustomizeDemo
    }
    showChangelogAgain: () => {
        value: true
    }
    showMe: (origin: TodayTourPoint) => {
        origin: TodayTourPoint
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayDesignChangelogLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        changelogShown: (isSeen: (key: string) => boolean) => boolean
    }
}

export type todayDesignChangelogLogicType = MakeLogicType<
    todayDesignChangelogLogicValues,
    todayDesignChangelogLogicActions,
    Record<string, any>,
    todayDesignChangelogLogicMeta
>

/**
 * The beta design changelog: a card at the foot of the rail, shown to each person once, whose "Show me" plays a
 * cursor demo that ends in the Customize navigation dialog with a tip.
 */
export const todayDesignChangelogLogic = kea<todayDesignChangelogLogicType>([
    path(['layout', 'today', 'todayDesignChangelogLogic']),
    connect(() => ({
        values: [
            todaySeenLogic,
            ['isSeen'],
            todayRailLayoutLogic,
            ['railHidden', 'arrangedPanes'],
            navSwitchLogic,
            ['newNavDialogOpen'],
        ],
        actions: [todaySeenLogic, ['markSeen', 'markUnseen'], todayRailLayoutLogic, ['setCustomizeOpen']],
    })),
    actions({
        dismissChangelog: true,
        showMe: (origin: TodayTourPoint) => ({ origin }),
        setDemo: (demo: TodayCustomizeDemo) => ({ demo }),
        endDemo: true,
        showChangelogAgain: true,
        setCustomizeHint: (shown: boolean) => ({ shown }),
    }),
    reducers({
        demo: [
            null as TodayCustomizeDemo | null,
            {
                setDemo: (_, { demo }) => demo,
                endDemo: () => null,
            },
        ],
        // The demo's last step, shown in the dialog until the person closes it or the dialog.
        customizeHint: [
            false,
            {
                setCustomizeHint: (_, { shown }) => shown,
                setCustomizeOpen: (state, { open }) => open && state,
            },
        ],
    }),
    selectors({
        changelogShown: [(s) => [s.isSeen], (isSeen: (key: string) => boolean) => !isSeen(DESIGN_CHANGELOG_KEY)],
    }),
    listeners(({ actions, values }) => ({
        dismissChangelog: () => {
            actions.markSeen(DESIGN_CHANGELOG_KEY)
            // pinned: analytics event name and property. Renaming them breaks dashboards.
            posthog.capture('today design changelog', { action: 'dismiss' })
        },
        showMe: ({ origin }) => {
            actions.markSeen(DESIGN_CHANGELOG_KEY)
            posthog.capture('today design changelog', { action: 'show me' })
            // Read once here, so turning Chats on mid-demo does not change the steps it already planned.
            const explainChats = values.arrangedPanes.includes(CHATS_PANE) && values.railHidden.includes(CHATS_PANE)
            actions.setDemo({ origin, explainChats })
        },
        showChangelogAgain: () => actions.markUnseen(DESIGN_CHANGELOG_KEY),
    })),
    subscriptions(({ actions }) => ({
        // Someone switching to the new design now meets it whole, so a changelog of what changed would mean nothing to
        // them. The welcome dialog marks that moment, including on the first mount after the switch.
        newNavDialogOpen: (open: boolean) => {
            if (open) {
                actions.markSeen(DESIGN_CHANGELOG_KEY)
            }
        },
    })),
])
