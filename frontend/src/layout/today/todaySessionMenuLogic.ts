import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { router } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import { ApiError, readableErrorMessage } from 'lib/api-error'
import { fullName } from 'lib/utils/strings'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { UserBasicType } from '~/types'

import {
    tasksHandoffCreate,
    tasksPartialUpdate,
    tasksPinCreate,
    tasksRunsAnalyzeCreate,
} from 'products/tasks/frontend/generated/api'
import { PatchedTaskWriteApi } from 'products/tasks/frontend/generated/api.schemas'

import { todaySpacesLogic } from './todaySpacesLogic'

export type TodaySessionSurface = 'sidebar' | 'feed'

function serverMessage(error: unknown): string | undefined {
    return error instanceof ApiError ? readableErrorMessage(error.data) : undefined
}

