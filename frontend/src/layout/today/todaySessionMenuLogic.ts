export type todaySessionMenuLogicType = MakeLogicType<todaySessionMenuLogicValues, todaySessionMenuLogicActions>

export const todaySessionMenuLogic = kea<todaySessionMenuLogicType>([
    path(['layout', 'today', 'todaySessionMenuLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [todaySpacesLogic, ['loadPinnedTasks', 'loadRecentTasks']],
    })),
    actions({
        setSessionPinned: (sessionId: string, pinned: boolean) => ({ sessionId, pinned }),
        renameSession: (sessionId: string, title: string) => ({ sessionId, title }),
        archiveSession: (sessionId: string, archived: boolean) => ({ sessionId, archived }),
        moveSession: (sessionId: string, spaceId: string) => ({ sessionId, spaceId }),
        sessionUpdated: (sessionId: string) => ({ sessionId }),
        sessionUpdateFailed: (sessionId: string) => ({ sessionId }),
        startRenaming: (sessionId: string, surface: TodaySessionSurface) => ({ sessionId, surface }),
        stopRenaming: true,
        openHandoff: (menuId: string) => ({ menuId }),
        closeHandoff: true,
        setHandoffUser: (user: UserBasicType | null) => ({ user }),
        handOffSession: (sessionId: string, user: UserBasicType) => ({ sessionId, user }),
        analyzeSession: (sessionId: string, runId: string) => ({ sessionId, runId }),
    }),
    reducers({
        renaming: [
            null as { sessionId: string; surface: TodaySessionSurface } | null,
            {
                startRenaming: (_, { sessionId, surface }) => ({ sessionId, surface }),
                stopRenaming: () => null,
                renameSession: () => null,
            },
        ],
        handoffMenuId: [
            null as string | null,
            {
                openHandoff: (_, { menuId }) => menuId,
                closeHandoff: () => null,
            },
        ],
        handoffUser: [
            null as UserBasicType | null,
            {
                openHandoff: () => null,
                closeHandoff: () => null,
                setHandoffUser: (_, { user }) => user,
            },
        ],
        pendingSessionIds: [
            [] as string[],
            {
                setSessionPinned: (state, { sessionId }) => [...state, sessionId],
                renameSession: (state, { sessionId }) => [...state, sessionId],
                archiveSession: (state, { sessionId }) => [...state, sessionId],
                moveSession: (state, { sessionId }) => [...state, sessionId],
                handOffSession: (state, { sessionId }) => [...state, sessionId],
                analyzeSession: (state, { sessionId }) => [...state, sessionId],
                sessionUpdated: (state, { sessionId }) => state.filter((id) => id !== sessionId),
                sessionUpdateFailed: (state, { sessionId }) => state.filter((id) => id !== sessionId),
            },
        ],
    }),
    listeners(({ actions, values }) => {
        const update = async (sessionId: string, patch: PatchedTaskWriteApi, failure: string): Promise<boolean> => {
            try {
                await tasksPartialUpdate(String(values.currentTeamId), sessionId, patch)
                actions.sessionUpdated(sessionId)
                return true
            } catch {
                lemonToast.error(failure)
                actions.sessionUpdateFailed(sessionId)
                return false
            }
        }

        return {
            setSessionPinned: async ({ sessionId, pinned }) => {
                try {
                    await tasksPinCreate(String(values.currentTeamId), sessionId, { pinned })
                    actions.sessionUpdated(sessionId)
                } catch {
                    lemonToast.error(`Couldn’t ${pinned ? 'pin' : 'unpin'} this session. Try again.`)
                    actions.sessionUpdateFailed(sessionId)
                }
            },
            renameSession: async ({ sessionId, title }) => {
                await update(sessionId, { title, title_manually_set: true }, 'Couldn’t rename this session. Try again.')
            },
            archiveSession: async ({ sessionId, archived }) => {
                const done = await update(
                    sessionId,
                    { archived },
                    `Couldn’t ${archived ? 'archive' : 'restore'} this session. Try again.`
                )
                if (done && archived) {
                    lemonToast.success('Session archived', {
                        button: {
                            label: 'Undo',
                            action: () => actions.archiveSession(sessionId, false),
                            dataAttr: 'today-session-archive-undo',
                        },
                    })
                }
            },
            moveSession: async ({ sessionId, spaceId }) => {
                await update(sessionId, { channel: spaceId }, 'Couldn’t move this session. Try again.')
            },
            handOffSession: async ({ sessionId, user }) => {
                try {
                    await tasksHandoffCreate(String(values.currentTeamId), sessionId, { user: user.id })
                    lemonToast.success(`Session handed off to ${fullName(user)}`)
                    actions.closeHandoff()
                    actions.sessionUpdated(sessionId)
                } catch (error) {
                    lemonToast.error(serverMessage(error) ?? 'Couldn’t hand off this session. Try again.')
                    actions.sessionUpdateFailed(sessionId)
                }
            },
            analyzeSession: async ({ sessionId, runId }) => {
                try {
                    const { analysis_task_id, created } = await tasksRunsAnalyzeCreate(
                        String(values.currentTeamId),
                        sessionId,
                        runId
                    )
                    actions.sessionUpdated(sessionId)
                    lemonToast.success(created ? 'Analysis started' : 'This run already has an analysis', {
                        button: {
                            label: 'Open',
                            action: () => router.actions.push(urls.aiTask(analysis_task_id)),
                            dataAttr: 'today-session-analysis-open',
                        },
                    })
                } catch (error) {
                    lemonToast.error(serverMessage(error) ?? 'Couldn’t analyze this run. Try again.')
                    actions.sessionUpdateFailed(sessionId)
                }
            },
            sessionUpdated: () => {
                actions.loadPinnedTasks()
                actions.loadRecentTasks()
            },
        }
    }),
])
