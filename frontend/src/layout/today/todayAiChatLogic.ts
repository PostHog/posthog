/** The context panel's PostHog AI chat: which chat is open, its recent chats, and moving it to full screen. */
export const todayAiChatLogic = kea<todayAiChatLogicType>([
    path(['layout', 'today', 'todayAiChatLogic']),
    connect(() => ({
        values: [
            todaySpacesLogic,
            ['allRecentItems', 'pinnedItems', 'unreadSessionIds', 'recentLoading', 'taskActivity'],
            maxGlobalLogic,
            ['effectivePhaiView'],
            maxLogic({ panelId: SIDE_PANEL_PANEL_ID }),
            ['chatTitle as legacyChatTitle', 'conversationId'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['activeCreation'],
            attachedContextLogic,
            ['contextItems'],
            todayShellLogic,
            ['onAiPage', 'lastSceneUrl'],
            sidePanelStateLogic,
            ['selectedTabOptions'],
        ],
        actions: [
            maxGlobalLogic,
            ['setPhaiViewMode'],
            sidePanelStateLogic,
            ['setSidePanelOptions', 'openSidePanel'],
            todayContextPanelLogic,
            ['setFloatingOpen', 'setFloatingTab'],
            todaySpacesLogic,
            ['markSessionRead'],
            maxLogic({ panelId: SIDE_PANEL_PANEL_ID }),
            ['openConversation', 'startNewConversation'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setActiveCreation', 'clearActiveCreation', 'setHistoryExpanded'],
            attachedContextLogic,
            ['registerContext', 'deregisterContext'],
        ],
    })),
    actions({
        openRecentItem: (item: TodayWorkItem) => ({ item }),
        startNewChat: true,
        carryContextToFullScreen: true,
        moveChatToPanel: (mode: 'floating' | 'docked', chat: TodayPanelChatTask | null) => ({ mode, chat }),
    }),
    selectors({
        recentGroups: [
            (s) => [s.allRecentItems, s.pinnedItems],
            (allRecentItems: TodayWorkItem[], pinnedItems: TodayWorkItem[]): TodayWorkGroup[] =>
                groupByDay([...pinnedItems, ...allRecentItems].sort((first, second) => timeOf(second) - timeOf(first))),
        ],
        activeItemId: [
            (s) => [s.effectivePhaiView, s.activeCreation, s.conversationId],
            (
                effectivePhaiView: PhaiViewMode,
                activeCreation: ActiveCreation | null,
                conversationId: string | null
            ): string | null => (effectivePhaiView === 'new' ? (activeCreation?.taskId ?? null) : conversationId),
        ],
        chatTitle: [
            (s) => [s.effectivePhaiView, s.activeItemId, s.allRecentItems, s.pinnedItems, s.legacyChatTitle],
            (
                effectivePhaiView: PhaiViewMode,
                activeItemId: string | null,
                allRecentItems: TodayWorkItem[],
                pinnedItems: TodayWorkItem[],
                legacyChatTitle: string | null
            ): string => {
                if (effectivePhaiView === 'legacy') {
                    return legacyChatTitle || 'PostHog AI'
                }
                if (!activeItemId) {
                    return 'New chat'
                }
                const item = [...pinnedItems, ...allRecentItems].find((recent) => recent.id === activeItemId)
                return item?.title || 'Untitled chat'
            },
        ],
        // Report and scout chats run on the task runner in either view, the same as the side panel's own header.
        onTaskRunner: [
            (s) => [s.effectivePhaiView, s.selectedTabOptions],
            (effectivePhaiView: PhaiViewMode, selectedTabOptions: string | null): boolean =>
                effectivePhaiView === 'new' ||
                selectedTabOptions === REPORT_AI_PANEL ||
                selectedTabOptions === SCOUT_AI_PANEL,
        ],
        fullScreenUrl: [
            (s) => [s.onTaskRunner, s.activeCreation, s.conversationId],
            (
                onTaskRunner: boolean,
                activeCreation: ActiveCreation | null,
                conversationId: string | null
            ): string | null => mainFocusUrl({ isNewView: onTaskRunner, activeCreation, conversationId }),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        startNewChat: () => {
            if (values.onTaskRunner) {
                actions.clearActiveCreation()
                // An expanded task history would otherwise stay in place of the composer.
                actions.setHistoryExpanded(false)
            } else {
                actions.startNewConversation()
            }
        },
        openRecentItem: ({ item }) => {
            // pinned: analytics event name
            posthog.capture('today context panel recent opened', { kind: item.kind })
            // A report or scout panel attaches its own entity's context, so it must not stay mounted on another chat.
            if (values.selectedTabOptions) {
                actions.setSidePanelOptions(null)
            }
            const newView = values.effectivePhaiView === 'new'
            if (item.kind === 'session') {
                if (newView && item.latestRunId) {
                    actions.setActiveCreation(runnerCreationFor({ taskId: item.id, runId: item.latestRunId }))
                    // Read tracking follows the /ai URL, which an inline open never changes, so mark it here.
                    const request = sessionReadRequest(values.taskActivity, item.id)
                    if (request) {
                        actions.markSessionRead(request.marker, request.activityIds)
                    }
                } else {
                    router.actions.push(urls.aiTask(item.id))
                }
                return
            }
            if (newView) {
                router.actions.push(urls.ai(item.id))
            } else {
                actions.openConversation(item.id)
            }
        },
        moveChatToPanel: ({ mode, chat }) => {
            // pinned: analytics event name
            posthog.capture('today ai task moved to panel', { mode, has_task: !!chat })
            // A report or scout panel attaches its own entity's context, so it must not stay on another chat.
            actions.setSidePanelOptions(null)
            if (chat) {
                // A task only renders in the new view's runner, so a saved legacy view would show another chat.
                if (values.effectivePhaiView !== 'new') {
                    actions.setPhaiViewMode('new')
                }
                actions.setActiveCreation(runnerCreationFor(chat))
            } else {
                actions.clearActiveCreation()
            }
            router.actions.push(values.lastSceneUrl ?? urls.projectHomepage())
            if (mode === 'docked') {
                actions.openSidePanel(SidePanelTab.Max)
            } else {
                actions.setFloatingTab(SidePanelTab.Max)
                actions.setFloatingOpen(true)
            }
        },
        // The chat's context comes from the scene behind it, and that scene unmounts on the way to /ai. A copy of
        // what the composer shows rides along, so the full screen chat still knows what the user was looking at.
        carryContextToFullScreen: () => {
            if (values.contextItems.length > 0) {
                actions.registerContext(FULL_SCREEN_CONTEXT_PROVIDER_ID, values.contextItems)
                cache.fullScreenContext = 'pending'
            }
        },
        // Closing the panel changes the URL before the page leaves the scene, so the copy is dropped only once the
        // user has reached /ai and then left it.
        [router.actionTypes.locationChanged]: () => {
            if (values.onAiPage) {
                if (cache.fullScreenContext === 'pending') {
                    cache.fullScreenContext = 'shown'
                }
            } else if (cache.fullScreenContext === 'shown') {
                cache.fullScreenContext = null
                actions.deregisterContext(FULL_SCREEN_CONTEXT_PROVIDER_ID)
            }
        },
    })),
])
