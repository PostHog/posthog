import { router } from 'kea-router'
import { subscriptions } from 'kea-subscriptions'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { getCurrentTeamIdOrNone, getCurrentUserIdOrNone } from 'lib/utils/getAppContext'
import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { Scene } from 'scenes/sceneTypes'

import { breadcrumbsLogic } from '~/layout/navigation/Breadcrumbs/breadcrumbsLogic'
import { Breadcrumb } from '~/types'

export type TodayPeopleRecentType = 'person' | 'group' | 'cohort' | 'account' | 'ticket'

export interface TodayPeopleRecent {
    type: TodayPeopleRecentType
    name: string
    href: string
}

interface TodayPeopleRecentSource {
    type: TodayPeopleRecentType
    /** The start of the page's path. What follows, like a tab, opens the same recent. */
    path: RegExp
    /** The scene that owns the page's last breadcrumb, which names the recent. */
    scene: string
}

// To track another kind of page, add a type and a line here, and give the type an icon in TodayPeopleSidebar.
export const TODAY_PEOPLE_RECENT_SOURCES: TodayPeopleRecentSource[] = [
    { type: 'person', path: /^\/persons?\/[^/]+/, scene: Scene.Person },
    { type: 'group', path: /^\/groups\/\d+\/(?!new(?:\/|$))[^/]+/, scene: Scene.Group },
    { type: 'cohort', path: /^\/cohorts\/(?!new(?:\/|$))[^/]+/, scene: Scene.Cohort },
    {
        type: 'account',
        path: /^\/customer_analytics\/accounts\/(?:by-external-id\/[^/]+|[^/]+)/,
        scene: Scene.CustomerAnalyticsAccount,
    },
    { type: 'ticket', path: /^\/support\/tickets\/(?!new(?:\/|$))[^/]+/, scene: 'SupportTicketDetail' },
]

export const TODAY_PEOPLE_RECENTS_LIMIT = 10

/** The recent for the open page, or null for other pages and while the page's own breadcrumb has not loaded. */
export function peopleRecentForPage(pathname: string, breadcrumbs: Breadcrumb[]): TodayPeopleRecent | null {
    const path = removeProjectIdIfPresent(pathname)
    const crumb = breadcrumbs[breadcrumbs.length - 1]
    const crumbScene = Array.isArray(crumb?.key) ? crumb.key[0] : crumb?.key
    for (const source of TODAY_PEOPLE_RECENT_SOURCES) {
        const href = path.match(source.path)?.[0]
        if (href) {
            return crumbScene === source.scene && crumb.name && typeof crumb.name === 'string'
                ? { type: source.type, name: crumb.name, href }
                : null
        }
    }
    return null
}

/** Puts a visit first. Reloading the same page changes nothing, so the list stays stable while a page loads. */
export function addPeopleRecent(recents: TodayPeopleRecent[], recent: TodayPeopleRecent): TodayPeopleRecent[] {
    const [first] = recents
    if (first?.href === recent.href && first.name === recent.name) {
        return recents
    }
    return [recent, ...recents.filter((item) => item.href !== recent.href)].slice(0, TODAY_PEOPLE_RECENTS_LIMIT)
}

// Recents belong to one person in one project. Without both ids nothing persists.
const TEAM_ID = getCurrentTeamIdOrNone()
const USER_ID = getCurrentUserIdOrNone()
const RECENTS_PERSIST_OPTIONS =
    TEAM_ID && USER_ID ? { persist: true, prefix: `${TEAM_ID}__${USER_ID}__` } : { persist: false }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayPeopleRecentsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    location: {
        pathname: string
        search: string
        hash: string
    } // router
    sceneBreadcrumbs: Breadcrumb[] // breadcrumbsLogic
    currentRecent: TodayPeopleRecent | null
    recents: TodayPeopleRecent[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayPeopleRecentsLogicActions {
    addRecent: (recent: TodayPeopleRecent) => {
        recent: TodayPeopleRecent
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayPeopleRecentsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        currentRecent: (
            featureFlags: FeatureFlagsSet,
            location: {
                hash: string
                pathname: string
                search: string
            },
            sceneBreadcrumbs: Breadcrumb[]
        ) => TodayPeopleRecent | null
    }
}

export type todayPeopleRecentsLogicType = MakeLogicType<
    todayPeopleRecentsLogicValues,
    todayPeopleRecentsLogicActions,
    Record<string, any>,
    todayPeopleRecentsLogicMeta
>

/** Mounted with the shell, so a person opened from any pane counts. */
export const todayPeopleRecentsLogic = kea<todayPeopleRecentsLogicType>([
    path(['layout', 'today', 'todayPeopleRecentsLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], router, ['location'], breadcrumbsLogic, ['sceneBreadcrumbs']],
    })),
    actions({
        addRecent: (recent: TodayPeopleRecent) => ({ recent }),
    }),
    reducers({
        recents: [
            [] as TodayPeopleRecent[],
            RECENTS_PERSIST_OPTIONS,
            {
                addRecent: (state, { recent }) => addPeopleRecent(state, recent),
            },
        ],
    }),
    selectors({
        currentRecent: [
            (s) => [s.featureFlags, s.location, s.sceneBreadcrumbs],
            (
                featureFlags: FeatureFlagsSet,
                location: { pathname: string },
                sceneBreadcrumbs: Breadcrumb[]
            ): TodayPeopleRecent | null =>
                featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV]
                    ? peopleRecentForPage(location.pathname, sceneBreadcrumbs)
                    : null,
        ],
    }),
    subscriptions(({ actions }) => ({
        currentRecent: (recent: TodayPeopleRecent | null) => {
            if (recent) {
                actions.addRecent(recent)
            }
        },
    })),
])
