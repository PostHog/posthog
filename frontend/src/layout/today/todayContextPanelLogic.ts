/**
 * The context panel outside the scene: a floating card over the main content, or docked in the side panel.
 * Both show the same panel, so only one of them is open at a time. PostHog AI is the panel's home tab.
 */
export const todayContextPanelLogic = kea<todayContextPanelLogicType>([
    path(['layout', 'today', 'todayContextPanelLogic']),
    connect(() => ({
        values: [
            sidePanelStateLogic,
            ['sidePanelOpen', 'selectedTab'],
            sidePanelLogic,
            ['enabledTabs'],
            notebookPanelLogic,
            ['selectedNotebook'],
            sidepanelTicketsLogic,
            ['tickets', 'canCreateTicket', 'view as supportView', 'currentTicket'],
            todayShellLogic,
            ['onAiPage'],
        ],
        actions: [sidePanelStateLogic, ['openSidePanel', 'closeSidePanel']],
    })),
    actions({
        setFloatingOpen: (open: boolean) => ({ open }),
        setFloatingTab: (tab: SidePanelTab) => ({ tab }),
        setFloatingOffset: (offset: TodayContextPanelOffset) => ({ offset }),
        setDockHint: (dockHint: boolean) => ({ dockHint }),
        setLauncherAlign: (align: TodayLauncherAlign) => ({ align }),
        hideLauncher: true,
        showLauncherHint: true,
        hideLauncherHint: true,
        togglePanelTab: (tab: SidePanelTab) => ({ tab }),
        dock: true,
        undock: true,
        close: true,
        openFullScreen: true,
    }),
    // A reload opens the card where it was, as state rather than an action, so it doesn't count as the user opening it.
    defaults(() => {
        const saved = readSessionValue<TodayFloatingSession>(projectSessionKey(FLOATING_SESSION_KEY))
        return saved ? { floatingOpen: true, floatingTab: saved.tab, floatingOffset: saved.offset } : {}
    }),
    reducers({
        floatingOpen: [
            false,
            {
                setFloatingOpen: (_, { open }) => open,
                dock: () => false,
                undock: () => true,
            },
        ],
        floatingTab: [
            SidePanelTab.Max as SidePanelTab,
            {
                setFloatingTab: (_, { tab }) => tab,
            },
        ],
        // Kept across opens, so the panel comes back where the user left it.
        floatingOffset: [
            NO_OFFSET as TodayContextPanelOffset,
            {
                setFloatingOffset: (_, { offset }) => offset,
            },
        ],
        launcherAlign: [
            'end' as TodayLauncherAlign,
            { persist: true },
            {
                setLauncherAlign: (_, { align }) => align,
            },
        ],
        launcherHiddenByUser: [
            false,
            { persist: true },
            {
                hideLauncher: () => true,
                // The card closes back into the floating button, so closing it brings the button back.
                setFloatingOpen: (state, { open }) => (open ? state : false),
            },
        ],
        launcherHintVisible: [
            false,
            {
                showLauncherHint: () => true,
                hideLauncherHint: () => false,
                togglePanelTab: () => false,
            },
        ],
        dockHint: [
            false,
            {
                setDockHint: (_, { dockHint }) => dockHint,
                dock: () => false,
                setFloatingOpen: () => false,
            },
        ],
    }),
    selectors({
        docked: [(s) => [s.sidePanelOpen], (sidePanelOpen: boolean): boolean => sidePanelOpen],
        floatingSession: [
            (s) => [s.floatingOpen, s.floatingActiveTab, s.floatingOffset],
            (
                floatingOpen: boolean,
                floatingActiveTab: SidePanelTab,
                floatingOffset: TodayContextPanelOffset
            ): TodayFloatingSession | null =>
                floatingOpen ? { tab: floatingActiveTab, offset: floatingOffset } : null,
        ],
        /**
         * The button sinks away while docked and where the scene has no PostHog AI. The open card hangs off it, so it
         * shows for as long as the card is open, even after the user dismissed it.
         */
        launcherHidden: [
            (s) => [s.docked, s.launcherHiddenByUser, s.floatingOpen, s.panelTabs],
            (
                docked: boolean,
                launcherHiddenByUser: boolean,
                floatingOpen: boolean,
                panelTabs: SidePanelTab[]
            ): boolean => docked || (launcherHiddenByUser && !floatingOpen) || !panelTabs.includes(SidePanelTab.Max),
        ],
        panelTabs: [
            (s) => [s.enabledTabs],
            // PostHog AI goes last, and only where the scene offers it. Canvas scenes bring their own chat.
            (enabledTabs: SidePanelTab[]): SidePanelTab[] => [
                ...enabledTabs.filter((tab) => tab !== SidePanelTab.Max && !TABS_LEFT_OUT.includes(tab)),
                ...(enabledTabs.includes(SidePanelTab.Max) ? [SidePanelTab.Max] : []),
            ],
        ],
        /**
         * A tab the scene no longer offers falls back to PostHog AI, like the docked panel closing on navigation.
         * Checked against every enabled tab, so an undocked tab the top bar leaves out stays open.
         */
        floatingActiveTab: [
            (s) => [s.floatingTab, s.enabledTabs],
            (floatingTab: SidePanelTab, enabledTabs: SidePanelTab[]): SidePanelTab =>
                enabledTabs.includes(floatingTab) && !CANVAS_SIDE_PANEL_TABS.includes(floatingTab)
                    ? floatingTab
                    : SidePanelTab.Max,
        ],
        /**
         * Canvas tabs read their body from the docked panel's selected tab, so they only dock. The AI page has no
         * floating panel to undock into.
         */
        canUndock: [
            (s) => [s.activeTab, s.onAiPage],
            (activeTab: SidePanelTab, onAiPage: boolean): boolean =>
                !onAiPage && !CANVAS_SIDE_PANEL_TABS.includes(activeTab),
        ],
        activeTab: [
            (s) => [s.docked, s.selectedTab, s.floatingActiveTab],
            (docked: boolean, selectedTab: SidePanelTab | null, floatingActiveTab: SidePanelTab): SidePanelTab =>
                docked && selectedTab ? selectedTab : floatingActiveTab,
        ],
        fullScreenUrl: [
            // PostHog AI's URL comes from the chat logic, which the header reads only while the panel is open.
            (s) => [s.activeTab, s.selectedNotebook, s.tickets, s.canCreateTicket, s.supportView, s.currentTicket],
            (
                activeTab: SidePanelTab,
                selectedNotebook: string,
                tickets: ConversationTicket[],
                canCreateTicket: boolean,
                supportView: SidePanelViewState,
                currentTicket: ConversationTicket | null
            ): string | null => {
                switch (activeTab) {
                    case SidePanelTab.Activity:
                        return urls.advancedActivityLogs()
                    case SidePanelTab.Notebooks:
                        return urls.notebook(selectedNotebook)
                    // Matches the support panel's own expand button: the tickets page, on the open ticket if any.
                    case SidePanelTab.Support:
                        return canCreateTicket || tickets.length > 0
                            ? urls.myTickets(supportView === 'ticket' ? currentTicket?.id : undefined)
                            : null
                    default:
                        return null
                }
            },
        ],
    }),
    subscriptions({
        floatingSession: (session: TodayFloatingSession | null) =>
            writeSessionValue(projectSessionKey(FLOATING_SESSION_KEY), session),
    }),
    listeners(({ actions, values }) => ({
        setLauncherAlign: ({ align }) => {
            posthog.capture('today ai button moved', { align })
        },
        hideLauncher: () => {
            posthog.capture('today ai button hidden')
            actions.showLauncherHint()
        },
        showLauncherHint: async (_, breakpoint) => {
            await breakpoint(LAUNCHER_HIDDEN_HINT_MS)
            actions.hideLauncherHint()
        },
        setFloatingOpen: ({ open }) => {
            // pinned: analytics event names
            posthog.capture(open ? 'today context panel opened' : 'today context panel closed', {
                mode: 'floating',
                tab: values.floatingActiveTab,
            })
            if (open && values.docked) {
                actions.closeSidePanel()
            }
        },
        // The top bar's tab buttons: the open tab closes the panel, a floating panel switches in place, and with the
        // panel closed the tab opens docked.
        togglePanelTab: ({ tab }) => {
            const open = values.docked || values.floatingOpen
            posthog.capture('today context panel tab toggled', { tab, docked: values.docked, open })
            if (open && values.activeTab === tab) {
                actions.close()
            } else if (values.floatingOpen && !CANVAS_SIDE_PANEL_TABS.includes(tab)) {
                actions.setFloatingTab(tab)
            } else {
                actions.openSidePanel(tab)
            }
        },
        dock: () => {
            posthog.capture('today context panel docked', { tab: values.floatingActiveTab })
            actions.openSidePanel(values.floatingActiveTab)
        },
        undock: () => {
            const tab = values.selectedTab ?? SidePanelTab.Max
            posthog.capture('today context panel undocked', { tab })
            actions.setFloatingTab(tab)
            actions.closeSidePanel()
        },
        close: () => {
            if (values.docked) {
                actions.closeSidePanel()
            } else {
                actions.setFloatingOpen(false)
            }
        },
        openFullScreen: () => {
            actions.close()
        },
        // The floating and docked panel are one panel, so docking any tab takes the floating card away.
        openSidePanel: () => {
            if (values.floatingOpen) {
                actions.setFloatingOpen(false)
            }
        },
    })),
])
