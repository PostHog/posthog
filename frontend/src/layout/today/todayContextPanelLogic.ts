import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import posthog from 'posthog-js'

import { notebookPanelLogic } from 'scenes/notebooks/NotebookPanel/notebookPanelLogic'
import { urls } from 'scenes/urls'

import { sidePanelLogic } from '~/layout/navigation-3000/sidepanel/sidePanelLogic'
import { sidePanelStateLogic } from '~/layout/navigation-3000/sidepanel/sidePanelStateLogic'
import { SidePanelTab } from '~/types'

/**
 * Tabs the top bar doesn't offer. Info is on its way out under the Today layout. Exports, Notebooks and Discussion
 * still open docked from their own entry points, such as "Add to notebook" or a comment button.
 */
const TABS_LEFT_OUT = [SidePanelTab.Info, SidePanelTab.Exports, SidePanelTab.Notebooks, SidePanelTab.Discussion]

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayContextPanelLogicValues {
    selectedNotebook: string // notebookPanelLogic
    enabledTabs: SidePanelTab[] // sidePanelLogic
    selectedTab: SidePanelTab | null // sidePanelStateLogic
    sidePanelOpen: boolean // sidePanelStateLogic
    activeTab: SidePanelTab
    docked: boolean
    fullScreenUrl: string | null
    panelTabs: SidePanelTab[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayContextPanelLogicActions {
    closeSidePanel: (tab?: SidePanelTab | undefined) => {
        tab: SidePanelTab | undefined
    } // sidePanelStateLogic
    openSidePanel: (
        tab: SidePanelTab,
        options?: string | undefined
    ) => {
        options: string | undefined
        tab: SidePanelTab
    } // sidePanelStateLogic
    close: () => {
        value: true
    }
    openFullScreen: () => {
        value: true
    }
    togglePanelTab: (tab: SidePanelTab) => {
        tab: SidePanelTab
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayContextPanelLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        docked: (sidePanelOpen: boolean) => boolean
        panelTabs: (enabledTabs: SidePanelTab[]) => SidePanelTab[]
        activeTab: (selectedTab: SidePanelTab | null) => SidePanelTab
        fullScreenUrl: (activeTab: SidePanelTab, selectedNotebook: string) => string | null
    }
}

export type todayContextPanelLogicType = MakeLogicType<
    todayContextPanelLogicValues,
    todayContextPanelLogicActions,
    Record<string, any>,
    todayContextPanelLogicMeta
>

/** The context panel outside the scene, docked in its own column beside it. PostHog AI is the panel's home tab. */
export const todayContextPanelLogic = kea<todayContextPanelLogicType>([
    path(['layout', 'today', 'todayContextPanelLogic']),
    connect(() => ({
        values: [
            sidePanelStateLogic,
            ['sidePanelOpen', 'selectedTab'],
            sidePanelLogic,
            ['enabledTabs'],
            notebookPanelLogic,
            ['selectedNotebook'],
        ],
        actions: [sidePanelStateLogic, ['openSidePanel', 'closeSidePanel']],
    })),
    actions({
        togglePanelTab: (tab: SidePanelTab) => ({ tab }),
        close: true,
        openFullScreen: true,
    }),
    selectors({
        docked: [(s) => [s.sidePanelOpen], (sidePanelOpen: boolean): boolean => sidePanelOpen],
        panelTabs: [
            (s) => [s.enabledTabs],
            (enabledTabs: SidePanelTab[]): SidePanelTab[] => [
                ...enabledTabs.filter((tab) => tab !== SidePanelTab.Max && !TABS_LEFT_OUT.includes(tab)),
                SidePanelTab.Max,
            ],
        ],
        activeTab: [
            (s) => [s.selectedTab],
            (selectedTab: SidePanelTab | null): SidePanelTab => selectedTab ?? SidePanelTab.Max,
        ],
        fullScreenUrl: [
            (s) => [s.activeTab, s.selectedNotebook],
            (activeTab: SidePanelTab, selectedNotebook: string): string | null => {
                switch (activeTab) {
                    case SidePanelTab.Activity:
                        return urls.advancedActivityLogs()
                    case SidePanelTab.Notebooks:
                        return urls.notebook(selectedNotebook)
                    default:
                        return null
                }
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        // The top bar's tab buttons: the open tab closes the panel, and any other tab opens docked.
        togglePanelTab: ({ tab }) => {
            posthog.capture('today context panel tab toggled', { tab, docked: values.docked, open: values.docked })
            if (values.docked && values.activeTab === tab) {
                actions.close()
            } else {
                actions.openSidePanel(tab)
            }
        },
        close: () => {
            actions.closeSidePanel()
        },
        openFullScreen: () => {
            actions.close()
        },
    })),
])
