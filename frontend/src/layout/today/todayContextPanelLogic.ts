/**
 * The context panel outside the scene: a floating card over the main content, or docked in the side panel.
 * Both show the same panel, so only one of them is open at a time. PostHog AI is the panel's home tab.
 */
const FULL_SCREEN_CONTEXT_PROVIDER_ID = 'today-context-panel-full-screen'

export const todayContextPanelLogic = kea<todayContextPanelLogicType>([
    path(['layout', 'today', 'todayContextPanelLogic']),
    connect(() => ({
        values: [
            sidePanelStateLogic,
            ['sidePanelOpen', 'selectedTab'],
            sidePanelLogic,
            ['enabledTabs'],
            todaySpacesLogic,
            ['allRecentItems', 'pinnedItems', 'unreadSessionIds', 'recentLoading'],
            maxGlobalLogic,
            ['effectivePhaiView'],
            maxLogic({ panelId: SIDE_PANEL_PANEL_ID }),
            ['chatTitle as legacyChatTitle', 'conversationId'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['activeCreation'],
            notebookPanelLogic,
            ['selectedNotebook'],
            sidepanelTicketsLogic,
            ['tickets', 'canCreateTicket', 'view as supportView', 'currentTicket'],
            attachedContextLogic,
            ['contextItems'],
            todayShellLogic,
            ['onAiPage'],
        ],
        actions: [
            sidePanelStateLogic,
            ['openSidePanel', 'closeSidePanel'],
            maxLogic({ panelId: SIDE_PANEL_PANEL_ID }),
            ['openConversation', 'startNewConversation'],
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setActiveCreation', 'clearActiveCreation'],
            attachedContextLogic,
            ['registerContext', 'deregisterContext'],
        ],
    })),
    actions({
        setFloatingOpen: (open: boolean) => ({ open }),
        setFloatingTab: (tab: SidePanelTab) => ({ tab }),
        setFloatingOffset: (offset: TodayContextPanelOffset) => ({ offset }),
        setDockHint: (dockHint: boolean) => ({ dockHint }),
        togglePanelTab: (tab: SidePanelTab) => ({ tab }),
        dock: true,
        undock: true,
        close: true,
        openFullScreen: true,
        openRecentItem: (item: TodayWorkItem) => ({ item }),
        startNewChat: true,
    }),
    reducers({
        floatingOpen: [
            false,
            {
                setFloatingOpen: (_, { open }) => open,
                dock: () => false,
                undock: () => true,
            },
        ],
        floatingTab: [
            SidePanelTab.Max as SidePanelTab,
            {
                setFloatingTab: (_, { tab }) => tab,
            },
        ],
        // Kept across opens, so the panel comes back where the user left it.
        floatingOffset: [
            NO_OFFSET as TodayContextPanelOffset,
            {
                setFloatingOffset: (_, { offset }) => offset,
            },
        ],
        dockHint: [
            false,
            {
                setDockHint: (_, { dockHint }) => dockHint,
                dock: () => false,
                setFloatingOpen: () => false,
            },
        ],
    }),
    selectors({
        docked: [(s) => [s.sidePanelOpen], (sidePanelOpen: boolean): boolean => sidePanelOpen],
        panelTabs: [
            (s) => [s.enabledTabs],
            (enabledTabs: SidePanelTab[]): SidePanelTab[] => [
                ...enabledTabs.filter((tab) => tab !== SidePanelTab.Max && !TABS_LEFT_OUT.includes(tab)),
                SidePanelTab.Max,
            ],
        ],
        /** A tab the scene no longer offers falls back to PostHog AI, like the docked panel closing on navigation. */
        floatingActiveTab: [
            (s) => [s.floatingTab, s.panelTabs],
            (floatingTab: SidePanelTab, panelTabs: SidePanelTab[]): SidePanelTab =>
                panelTabs.includes(floatingTab) ? floatingTab : SidePanelTab.Max,
        ],
        activeTab: [
            (s) => [s.docked, s.selectedTab, s.floatingActiveTab],
            (docked: boolean, selectedTab: SidePanelTab | null, floatingActiveTab: SidePanelTab): SidePanelTab =>
                docked && selectedTab ? selectedTab : floatingActiveTab,
        ],
        recentGroups: [
            (s) => [s.allRecentItems, s.pinnedItems],
            (allRecentItems: TodayWorkItem[], pinnedItems: TodayWorkItem[]): TodayWorkGroup[] =>
                groupByDay([...pinnedItems, ...allRecentItems].sort((first, second) => timeOf(second) - timeOf(first))),
        ],
        activeItemId: [
            (s) => [s.effectivePhaiView, s.activeCreation, s.conversationId],
            (
                effectivePhaiView: PhaiViewMode,
                activeCreation: ActiveCreation | null,
                conversationId: string | null
            ): string | null => (effectivePhaiView === 'new' ? (activeCreation?.taskId ?? null) : conversationId),
        ],
        chatTitle: [
            (s) => [s.effectivePhaiView, s.activeItemId, s.allRecentItems, s.pinnedItems, s.legacyChatTitle],
            (
                effectivePhaiView: PhaiViewMode,
                activeItemId: string | null,
                allRecentItems: TodayWorkItem[],
                pinnedItems: TodayWorkItem[],
                legacyChatTitle: string | null
            ): string => {
                if (effectivePhaiView === 'legacy') {
                    return legacyChatTitle || 'PostHog AI'
                }
                if (!activeItemId) {
                    return 'New chat'
                }
                const item = [...pinnedItems, ...allRecentItems].find((recent) => recent.id === activeItemId)
                return item?.title || 'Untitled chat'
            },
        ],
        fullScreenUrl: [
            (s) => [
                s.activeTab,
                s.effectivePhaiView,
                s.activeCreation,
                s.conversationId,
                s.selectedNotebook,
                s.tickets,
                s.canCreateTicket,
                s.supportView,
                s.currentTicket,
            ],
            (
                activeTab: SidePanelTab,
                effectivePhaiView: PhaiViewMode,
                activeCreation: ActiveCreation | null,
                conversationId: string | null,
                selectedNotebook: string,
                tickets: ConversationTicket[],
                canCreateTicket: boolean,
                supportView: SidePanelViewState,
                currentTicket: ConversationTicket | null
            ): string | null => {
                switch (activeTab) {
                    case SidePanelTab.Max:
                        return mainFocusUrl({ isNewView: effectivePhaiView === 'new', activeCreation, conversationId })
                    case SidePanelTab.Activity:
                        return urls.advancedActivityLogs()
                    case SidePanelTab.Notebooks:
                        return urls.notebook(selectedNotebook)
                    // Matches the support panel's own expand button: the tickets page, on the open ticket if any.
                    case SidePanelTab.Support:
                        return canCreateTicket || tickets.length > 0
                            ? urls.myTickets(supportView === 'ticket' ? currentTicket?.id : undefined)
                            : null
                    default:
                        return null
                }
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setFloatingOpen: ({ open }) => {
            // pinned: analytics event names
            posthog.capture(open ? 'today context panel opened' : 'today context panel closed', {
                mode: 'floating',
                tab: values.floatingActiveTab,
            })
            if (open && values.docked) {
                actions.closeSidePanel()
            }
        },
        // The top bar's tab buttons: the open tab closes the panel, a floating panel switches in place, and with the
        // panel closed the tab opens docked.
        togglePanelTab: ({ tab }) => {
            const open = values.docked || values.floatingOpen
            posthog.capture('today context panel tab toggled', { tab, docked: values.docked, open })
            if (open && values.activeTab === tab) {
                actions.close()
            } else if (values.floatingOpen) {
                actions.setFloatingTab(tab)
            } else {
                actions.openSidePanel(tab)
            }
        },
        dock: () => {
            posthog.capture('today context panel docked', { tab: values.floatingActiveTab })
            actions.openSidePanel(values.floatingActiveTab)
        },
        undock: () => {
            const tab = values.selectedTab ?? SidePanelTab.Max
            posthog.capture('today context panel undocked', { tab })
            actions.setFloatingTab(tab)
            actions.closeSidePanel()
        },
        close: () => {
            if (values.docked) {
                actions.closeSidePanel()
            } else {
                actions.setFloatingOpen(false)
            }
        },
        // The chat's context comes from the scene behind it, and that scene unmounts on the way to /ai. A copy of
        // what the composer shows rides along, so the full screen chat still knows what the user was looking at.
        openFullScreen: () => {
            if (values.activeTab === SidePanelTab.Max && values.contextItems.length > 0) {
                actions.registerContext(FULL_SCREEN_CONTEXT_PROVIDER_ID, values.contextItems)
                cache.fullScreenContext = 'pending'
            }
            actions.close()
        },
        // Closing the panel changes the URL before the page leaves the scene, so the copy is dropped only once the
        // user has reached /ai and then left it.
        [router.actionTypes.locationChanged]: () => {
            if (values.onAiPage) {
                if (cache.fullScreenContext === 'pending') {
                    cache.fullScreenContext = 'shown'
                }
            } else if (cache.fullScreenContext === 'shown') {
                cache.fullScreenContext = null
                actions.deregisterContext(FULL_SCREEN_CONTEXT_PROVIDER_ID)
            }
        },
        // The floating and docked panel are one panel, so docking any tab takes the floating card away.
        openSidePanel: () => {
            if (values.floatingOpen) {
                actions.setFloatingOpen(false)
            }
        },
        startNewChat: () => {
            if (values.effectivePhaiView === 'new') {
                actions.clearActiveCreation()
            } else {
                actions.startNewConversation()
            }
        },
        openRecentItem: ({ item }) => {
            posthog.capture('today context panel recent opened', { kind: item.kind })
            const newView = values.effectivePhaiView === 'new'
            if (item.kind === 'session') {
                if (newView && item.latestRunId) {
                    actions.setActiveCreation({ streamKey: item.latestRunId, taskId: item.id, runId: item.latestRunId })
                } else {
                    router.actions.push(urls.aiTask(item.id))
                }
                return
            }
            if (newView) {
                router.actions.push(urls.ai(item.id))
            } else {
                actions.openConversation(item.id)
            }
        },
    })),
])
