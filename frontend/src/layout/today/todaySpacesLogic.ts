import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { maxGlobalLogic } from 'scenes/max/maxGlobalLogic'
import { teamLogic } from 'scenes/teamLogic'

import { ConversationDetail } from '~/types'

import { taskChannelsList, tasksList } from 'products/tasks/frontend/generated/api'
import { ChannelDTOApi, TaskListItemApi } from 'products/tasks/frontend/generated/api.schemas'

const SPACE_TASK_LIMIT = 8
const RECENT_CHAT_LIMIT = 12

/** The personal space first, then the team's general space, then starred spaces, then the rest by name. */
export function sortSpaces(spaces: ChannelDTOApi[]): ChannelDTOApi[] {
    const rank = (space: ChannelDTOApi): number =>
        space.system_role === 'personal' ? 0 : space.system_role === 'general' ? 1 : space.starred ? 2 : 3
    return [...spaces].sort((first, second) => rank(first) - rank(second) || first.name.localeCompare(second.name))
}

export function spaceLabel(space: Pick<ChannelDTOApi, 'name' | 'system_role'>): string {
    return space.system_role === 'personal' ? 'Me' : space.name
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todaySpacesLogicValues {
    conversationHistory: ConversationDetail[] // maxGlobalLogic
    conversationHistoryLoading: boolean // maxGlobalLogic
    currentTeamId: number | null // teamLogic
    expandedSpaceIds: string[]
    recentChats: ConversationDetail[]
    sortedSpaces: ChannelDTOApi[]
    spaceTasks: Record<string, TaskListItemApi[]>
    spaceTasksLoading: boolean
    spaces: ChannelDTOApi[]
    spacesLoading: boolean
    spacesUnavailable: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todaySpacesLogicActions {
    loadSpaceTasks: (spaceId: string) => string
    loadSpaceTasksFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSpaceTasksSuccess: (
        spaceTasks: Record<string, TaskListItemApi[]>,
        payload?: string
    ) => {
        spaceTasks: Record<string, TaskListItemApi[]>
        payload?: string
    }
    loadSpaces: () => any
    loadSpacesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSpacesSuccess: (
        spaces: ChannelDTOApi[],
        payload?: any
    ) => {
        spaces: ChannelDTOApi[]
        payload?: any
    }
    toggleSpace: (spaceId: string) => {
        spaceId: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todaySpacesLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        sortedSpaces: (spaces: ChannelDTOApi[]) => ChannelDTOApi[]
        recentChats: (conversationHistory: ConversationDetail[]) => ConversationDetail[]
    }
}

export type todaySpacesLogicType = MakeLogicType<
    todaySpacesLogicValues,
    todaySpacesLogicActions,
    Record<string, any>,
    todaySpacesLogicMeta
>

export const todaySpacesLogic = kea<todaySpacesLogicType>([
    path(['layout', 'today', 'todaySpacesLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], maxGlobalLogic, ['conversationHistory', 'conversationHistoryLoading']],
    })),
    actions({
        toggleSpace: (spaceId: string) => ({ spaceId }),
    }),
    loaders(({ values }) => ({
        spaces: [
            [] as ChannelDTOApi[],
            {
                loadSpaces: async () => {
                    if (!values.currentTeamId) {
                        return []
                    }
                    const response = await taskChannelsList(String(values.currentTeamId))
                    // Without `limit` the endpoint answers with a bare array rather than a page.
                    return Array.isArray(response) ? (response as ChannelDTOApi[]) : response.results
                },
            },
        ],
        spaceTasks: [
            {} as Record<string, TaskListItemApi[]>,
            {
                loadSpaceTasks: async (spaceId: string) => {
                    if (!values.currentTeamId) {
                        return values.spaceTasks
                    }
                    const response = await tasksList(String(values.currentTeamId), {
                        channel: spaceId,
                        basic: true,
                        limit: SPACE_TASK_LIMIT,
                    })
                    return { ...values.spaceTasks, [spaceId]: response.results }
                },
            },
        ],
    })),
    reducers({
        expandedSpaceIds: [
            [] as string[],
            { persist: true },
            {
                toggleSpace: (state, { spaceId }) =>
                    state.includes(spaceId) ? state.filter((id) => id !== spaceId) : [...state, spaceId],
            },
        ],
        spacesUnavailable: [false, { loadSpaces: () => false, loadSpacesFailure: () => true }],
    }),
    selectors({
        sortedSpaces: [(s) => [s.spaces], (spaces: ChannelDTOApi[]): ChannelDTOApi[] => sortSpaces(spaces)],
        recentChats: [
            (s) => [s.conversationHistory],
            (conversationHistory: ConversationDetail[]): ConversationDetail[] =>
                conversationHistory.slice(0, RECENT_CHAT_LIMIT),
        ],
    }),
    listeners(({ actions, values }) => ({
        toggleSpace: ({ spaceId }) => {
            if (values.expandedSpaceIds.includes(spaceId) && !values.spaceTasks[spaceId]) {
                actions.loadSpaceTasks(spaceId)
            }
        },
        loadSpacesSuccess: ({ spaces }) => {
            for (const space of spaces) {
                if (values.expandedSpaceIds.includes(space.id)) {
                    actions.loadSpaceTasks(space.id)
                }
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSpaces()
    }),
])
