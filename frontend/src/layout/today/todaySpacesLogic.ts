export const todaySpacesLogic = kea<todaySpacesLogicType>([
    path(['layout', 'today', 'todaySpacesLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            userLogic,
            ['user'],
            maxGlobalLogic,
            ['conversationHistory', 'conversationHistoryLoading'],
        ],
    })),
    actions({
        toggleSpace: (spaceId: string) => ({ spaceId }),
        loadSpaceTasks: (spaceId: string) => ({ spaceId }),
        setSpaceTasks: (spaceId: string, tasks: TaskListItemApi[]) => ({ spaceId, tasks }),
        loadSpaceTasksFailure: (spaceId: string) => ({ spaceId }),
        toggleSection: (sectionId: TodayWorkSectionId) => ({ sectionId }),
        setBrowsingSpaces: (browsingSpaces: boolean) => ({ browsingSpaces }),
        setSpaceStarred: (spaceId: string, starred: boolean) => ({ spaceId, starred }),
    }),
    loaders(({ values }) => ({
        spaces: [
            [] as ChannelDTOApi[],
            {
                loadSpaces: async () => {
                    if (!values.currentTeamId) {
                        return []
                    }
                    const response = await taskChannelsList(String(values.currentTeamId))
                    // Without `limit` the endpoint answers with a bare array rather than a page.
                    return Array.isArray(response) ? (response as ChannelDTOApi[]) : response.results
                },
            },
        ],
        pinnedTasks: [
            [] as TaskListItemApi[],
            {
                loadPinnedTasks: async () => {
                    if (!values.currentTeamId) {
                        return []
                    }
                    const response = await tasksList(String(values.currentTeamId), {
                        pinned: true,
                        basic: true,
                        limit: PINNED_SESSION_LIMIT,
                    })
                    return response.results
                },
            },
        ],
        recentTasks: [
            [] as TaskListItemApi[],
            {
                loadRecentTasks: async () => {
                    if (!values.currentTeamId || !values.user) {
                        return []
                    }
                    const response = await tasksList(String(values.currentTeamId), {
                        created_by: values.user.id,
                        ordering: '-last_activity_at',
                        basic: true,
                        limit: RECENT_SESSION_LIMIT,
                    })
                    return response.results
                },
            },
        ],
    })),
    reducers({
        expandedSpaceIds: [
            [] as string[],
            { persist: true },
            {
                toggleSpace: (state, { spaceId }) =>
                    state.includes(spaceId) ? state.filter((id) => id !== spaceId) : [...state, spaceId],
            },
        ],
        collapsedSections: [
            [] as TodayWorkSectionId[],
            { persist: true },
            {
                toggleSection: (state, { sectionId }) =>
                    state.includes(sectionId) ? state.filter((id) => id !== sectionId) : [...state, sectionId],
            },
        ],
        browsingSpaces: [
            false,
            { persist: true },
            {
                setBrowsingSpaces: (_, { browsingSpaces }) => browsingSpaces,
            },
        ],
        spaces: {
            setSpaceStarred: (state, { spaceId, starred }) =>
                state.map((space) => (space.id === spaceId ? { ...space, starred } : space)),
        },
        spacesUnavailable: [false, { loadSpaces: () => false, loadSpacesFailure: () => true }],
        // Each space loads on its own, so expanding several at once never drops one space's sessions.
        spaceTasks: [
            {} as Record<string, TaskListItemApi[]>,
            { setSpaceTasks: (state, { spaceId, tasks }) => ({ ...state, [spaceId]: tasks }) },
        ],
        loadingSpaceIds: [
            [] as string[],
            {
                loadSpaceTasks: (state, { spaceId }) => (state.includes(spaceId) ? state : [...state, spaceId]),
                setSpaceTasks: (state, { spaceId }) => state.filter((id) => id !== spaceId),
                loadSpaceTasksFailure: (state, { spaceId }) => state.filter((id) => id !== spaceId),
            },
        ],
        failedSpaceIds: [
            [] as string[],
            {
                loadSpaceTasks: (state, { spaceId }) => state.filter((id) => id !== spaceId),
                loadSpaceTasksFailure: (state, { spaceId }) => (state.includes(spaceId) ? state : [...state, spaceId]),
            },
        ],
    }),
    selectors({
        sortedSpaces: [(s) => [s.spaces], (spaces: ChannelDTOApi[]): ChannelDTOApi[] => sortSpaces(spaces)],
        visibleSpaces: [
            (s) => [s.browsingSpaces, s.sortedSpaces],
            (browsingSpaces: boolean, sortedSpaces: ChannelDTOApi[]): ChannelDTOApi[] =>
                browsingSpaces ? sortedSpaces : starredSpaces(sortedSpaces),
        ],
        pinnedItems: [
            (s) => [s.pinnedTasks],
            (pinnedTasks: TaskListItemApi[]): TodayWorkItem[] =>
                pinnedTasks.filter((task) => !task.archived).map(sessionItem),
        ],
        recentItems: [
            (s) => [s.recentTasks, s.conversationHistory, s.pinnedTasks],
            (
                recentTasks: TaskListItemApi[],
                conversationHistory: ConversationDetail[],
                pinnedTasks: TaskListItemApi[]
            ): TodayWorkItem[] =>
                buildRecentItems(
                    recentTasks,
                    conversationHistory,
                    pinnedTasks.map((task) => task.id),
                    RECENT_ITEM_LIMIT
                ),
        ],
        recentGroups: [
            (s) => [s.recentItems],
            (recentItems: TodayWorkItem[]): TodayWorkGroup[] => groupByDay(recentItems),
        ],
        recentLoading: [
            (s) => [s.recentTasksLoading, s.conversationHistoryLoading],
            (recentTasksLoading: boolean, conversationHistoryLoading: boolean): boolean =>
                recentTasksLoading || conversationHistoryLoading,
        ],
    }),
    listeners(({ actions, values }) => ({
        loadSpaceTasks: async ({ spaceId }) => {
            if (!values.currentTeamId) {
                actions.loadSpaceTasksFailure(spaceId)
                return
            }
            try {
                const response = await tasksList(String(values.currentTeamId), {
                    channel: spaceId,
                    basic: true,
                    limit: SPACE_TASK_LIMIT,
                })
                actions.setSpaceTasks(spaceId, response.results)
            } catch {
                actions.loadSpaceTasksFailure(spaceId)
            }
        },
        toggleSpace: ({ spaceId }) => {
            if (values.expandedSpaceIds.includes(spaceId) && !values.spaceTasks[spaceId]) {
                actions.loadSpaceTasks(spaceId)
            }
        },
        loadSpacesSuccess: ({ spaces }) => {
            for (const space of spaces) {
                if (values.expandedSpaceIds.includes(space.id)) {
                    actions.loadSpaceTasks(space.id)
                }
            }
        },
        setSpaceStarred: async ({ spaceId, starred }) => {
            if (!values.currentTeamId) {
                return
            }
            try {
                await taskChannelsStarCreate(String(values.currentTeamId), spaceId, { starred })
            } catch {
                lemonToast.error(`Couldn’t ${starred ? 'star' : 'unstar'} this space. Try again.`)
                actions.loadSpaces()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSpaces()
        actions.loadPinnedTasks()
        actions.loadRecentTasks()
    }),
])
