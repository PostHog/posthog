export const waysToUseLogic = kea<waysToUseLogicType>([
    path(['layout', 'today', 'waysToUse', 'waysToUseLogic']),

    connect(() => ({
        values: [
            timeSensitiveAuthenticationLogic,
            ['showAuthenticationModal'],
            twoFactorLogic,
            ['forceOpenTwoFactorSetupModal'],
            sceneLogic,
            ['sceneKey'],
            teamLogic,
            ['currentTeam'],
            todayShellLogic,
            ['todayRailEnabled', 'phoneLayout'],
            userLogic,
            ['user', 'isProvisionedUser'],
            welcomeDialogLogic,
            [
                'welcomeDataLoading',
                'hasLoadedOnce as welcomeDataLoaded',
                'welcomeDataError',
                'recentActivity',
                'popularDashboards',
                'productsInUse',
                'teamMembers',
            ],
        ],
        actions: [userLogic, ['updateHasSeenProductIntroFor'], welcomeDialogLogic, ['loadWelcomeData']],
    })),

    actions({
        closeWaysToUse: (source: WaysToUseCloseSource, surface: WaysToUseSurface | null = null) => ({
            source,
            surface,
        }),
        reportShown: true,
        markSettled: true,
        setIntegrations: (integrations: IntegrationType[]) => ({ integrations }),
        goToStep: (index: number) => ({ index }),
        trackWaysToUseClick: (surface: WaysToUseSurface) => ({ surface }),
    }),

    reducers({
        settled: [
            false,
            {
                markSettled: () => true,
            },
        ],
        closed: [
            false,
            {
                closeWaysToUse: () => true,
            },
        ],
        shownReported: [
            false,
            {
                reportShown: () => true,
            },
        ],
        stepIndex: [
            0,
            {
                goToStep: (_, { index }) => index,
            },
        ],
        integrations: [
            null as IntegrationType[] | null,
            {
                setIntegrations: (_, { integrations }) => integrations,
            },
        ],
    }),

    selectors({
        forcedVariant: [
            () => [router.selectors.searchParams],
            (searchParams: Record<string, any>): WaysToUseVariant | null =>
                parseVariantParam(searchParams[WAYS_TO_USE_PARAM]),
        ],
        forced: [
            (s) => [s.todayRailEnabled, router.selectors.searchParams, s.forcedVariant],
            (
                todayRailEnabled: boolean,
                searchParams: Record<string, any>,
                forcedVariant: WaysToUseVariant | null
            ): boolean =>
                todayRailEnabled && (!!forcedVariant || parseSampleParam(searchParams[WAYS_TO_USE_PARAM]) === true),
        ],
        variant: [
            (s) => [s.forcedVariant, s.user, s.isProvisionedUser],
            (
                forcedVariant: WaysToUseVariant | null,
                user: UserType | null,
                isProvisionedUser: boolean
            ): WaysToUseVariant => forcedVariant ?? waysToUseVariant(user, isProvisionedUser),
        ],
        blocked: [
            (s) => [s.forceOpenTwoFactorSetupModal, s.showAuthenticationModal],
            (forceOpenTwoFactorSetupModal: boolean, showAuthenticationModal: boolean): boolean =>
                forceOpenTwoFactorSetupModal || showAuthenticationModal,
        ],
        eligible: [
            (s) => [s.todayRailEnabled, s.sceneKey, s.user, s.blocked],
            (todayRailEnabled: boolean, sceneKey: string | null, user: UserType | null, blocked: boolean): boolean =>
                shouldOfferWaysToUse({
                    todayRailEnabled,
                    onHome: sceneKey === 'projectHomepage',
                    user,
                    blocked,
                    now: Date.now(),
                }),
        ],
        wanted: [(s) => [s.eligible, s.forced], (eligible: boolean, forced: boolean): boolean => eligible || forced],
        teamWork: [
            (s) => [s.popularDashboards, s.recentActivity],
            (
                popularDashboards: WelcomePopularDashboard[],
                recentActivity: WelcomeRecentActivity[]
            ): WaysToUseTeamWorkItem[] => teamWorkItems(popularDashboards, recentActivity),
        ],
        steps: [
            (s) => [s.variant, s.teamWork, s.productsInUse, s.teamMembers],
            (
                variant: WaysToUseVariant,
                teamWork: WaysToUseTeamWorkItem[],
                productsInUse: string[],
                teamMembers: WelcomeTeamMember[]
            ): WaysToUseStep[] =>
                waysToUseSteps(variant, teamWork.length > 0 || productsInUse.length > 0 || teamMembers.length > 0),
        ],
        currentStep: [
            (s) => [s.steps, s.stepIndex],
            (steps: WaysToUseStep[], stepIndex: number): WaysToUseStep => steps[Math.min(stepIndex, steps.length - 1)],
        ],
        slackState: [
            (s) => [s.integrations, s.currentTeam],
            (integrations: IntegrationType[] | null, currentTeam: TeamType | null): WaysToUseSlackState =>
                waysToUseSlackState(integrations ?? [], currentTeam?.effective_membership_level),
        ],
        contentReady: [
            (s) => [s.integrations, s.variant, s.welcomeDataLoaded, s.welcomeDataError],
            (
                integrations: IntegrationType[] | null,
                variant: WaysToUseVariant,
                welcomeDataLoaded: boolean,
                welcomeDataError: boolean
            ): boolean => integrations !== null && (variant === 'creator' || welcomeDataLoaded || welcomeDataError),
        ],
        isOpen: [
            (s) => [s.settled, s.closed, s.contentReady, s.blocked, s.wanted],
            (settled: boolean, closed: boolean, contentReady: boolean, blocked: boolean, wanted: boolean): boolean =>
                settled && !closed && contentReady && !blocked && wanted,
        ],
    }),

    listeners(({ actions, values }) => ({
        [integrationsLogic.actionTypes.loadIntegrationsSuccess]: ({ integrations }) => {
            actions.setIntegrations(integrations)
        },
        [integrationsLogic.actionTypes.loadIntegrationsFailure]: () => {
            actions.setIntegrations([])
        },
        trackWaysToUseClick: ({ surface }) => {
            if (values.forced) {
                return
            }
            posthog.capture('today ways to use clicked', {
                surface,
                step: values.currentStep,
                variant: values.variant,
                phone_layout: values.phoneLayout,
            })
        },
        reportShown: () => {
            posthog.capture('today ways to use shown', {
                variant: values.variant,
                steps: values.steps,
                slack_state: values.slackState,
                phone_layout: values.phoneLayout,
            })
        },
        closeWaysToUse: ({ source, surface }) => {
            const seenKey = values.user ? waysToUseSeenKey(values.user) : null
            if (values.forced || !seenKey) {
                return
            }
            actions.updateHasSeenProductIntroFor(seenKey)
            posthog.capture('today ways to use closed', {
                source,
                surface,
                step: values.currentStep,
                variant: values.variant,
                slack_state: values.slackState,
                phone_layout: values.phoneLayout,
            })
        },
    })),

    disposables(({ actions }) => ({
        settleTimer: () => {
            const timerId = window.setTimeout(() => actions.markSettled(), SETTLE_MS)
            return () => clearTimeout(timerId)
        },
    })),

    subscriptions(({ actions, values, cache }) => ({
        wanted: (wanted: boolean) => {
            if (!wanted) {
                return
            }
            if (values.integrations === null) {
                cache.disposables.add(() => integrationsLogic.mount(), 'integrations', { pauseOnPageHidden: false })
                const loaded = integrationsLogic.values.integrations
                if (loaded) {
                    actions.setIntegrations(loaded)
                }
            }
            if (values.variant === 'invitee' && !values.welcomeDataLoaded && !values.welcomeDataLoading) {
                actions.loadWelcomeData()
            }
        },
        isOpen: (isOpen: boolean) => {
            if (isOpen && !values.forced && !values.shownReported) {
                actions.reportShown()
            }
        },
    })),
])
