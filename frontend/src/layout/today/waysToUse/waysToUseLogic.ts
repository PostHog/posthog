export type waysToUseLogicType = MakeLogicType<
    waysToUseLogicValues,
    waysToUseLogicActions,
    Record<string, any>,
    waysToUseLogicMeta
>

export const waysToUseLogic = kea<waysToUseLogicType>([
    path(['layout', 'today', 'waysToUse', 'waysToUseLogic']),

    connect(() => ({
        values: [
            todayShellLogic,
            ['todayRailEnabled', 'phoneLayout'],
            userLogic,
            ['user'],
            sceneLogic,
            ['sceneId'],
            welcomeDialogLogic,
            ['shouldShowDialog as welcomeDialogDue'],
        ],
        actions: [
            userLogic,
            ['updateHasSeenProductIntroFor'],
            welcomeDialogLogic,
            ['markShown', 'closeDialog', 'dismissWelcome'],
        ],
    })),

    actions({
        closeWaysToUse: (source: WaysToUseCloseSource, surface: WaysToUseSurface | null = null) => ({
            source,
            surface,
        }),
        surfaceLinkClicked: (surface: WaysToUseSurface, opensNewTab: boolean) => ({ surface, opensNewTab }),
        reportShown: true,
    }),

    reducers({
        closed: [
            false,
            {
                closeWaysToUse: () => true,
            },
        ],
        shownReported: [
            false,
            {
                reportShown: () => true,
            },
        ],
        welcomeDialogSeenThisSession: [
            false,
            {
                markShown: () => true,
                closeDialog: () => true,
                dismissWelcome: () => true,
            },
        ],
    }),

    selectors({
        forced: [
            (s) => [s.todayRailEnabled, router.selectors.searchParams],
            (todayRailEnabled: boolean, searchParams: Record<string, any>): boolean =>
                todayRailEnabled && parseWaysToUseParam(searchParams[WAYS_TO_USE_PARAM]),
        ],
        eligible: [
            (s) => [s.todayRailEnabled, s.sceneId, s.user, s.welcomeDialogDue, s.welcomeDialogSeenThisSession],
            (
                todayRailEnabled: boolean,
                sceneId: string | null,
                user: UserType | null,
                welcomeDialogDue: boolean,
                welcomeDialogSeenThisSession: boolean
            ): boolean =>
                shouldOfferWaysToUse({
                    todayRailEnabled,
                    onHome: sceneId === Scene.ProjectHomepage,
                    user,
                    welcomeDialogDue: welcomeDialogDue || welcomeDialogSeenThisSession,
                    now: Date.now(),
                }),
        ],
        isOpen: [
            (s) => [s.closed, s.forced, s.eligible],
            (closed: boolean, forced: boolean, eligible: boolean): boolean => !closed && (forced || eligible),
        ],
    }),

    listeners(({ actions, values }) => ({
        reportShown: () => {
            posthog.capture('today ways to use shown', { phone_layout: values.phoneLayout })
        },
        surfaceLinkClicked: ({ surface, opensNewTab }) => {
            if (!values.forced) {
                posthog.capture('today ways to use link clicked', { surface, phone_layout: values.phoneLayout })
            }
            if (!opensNewTab) {
                actions.closeWaysToUse('surface_link', surface)
            }
        },
        closeWaysToUse: ({ source, surface }) => {
            if (values.forced) {
                return
            }
            actions.updateHasSeenProductIntroFor(WAYS_TO_USE_SEEN_KEY)
            posthog.capture('today ways to use closed', {
                source,
                surface,
                phone_layout: values.phoneLayout,
            })
        },
    })),

    subscriptions(({ actions, values }) => ({
        isOpen: (isOpen: boolean) => {
            if (isOpen && !values.forced && !values.shownReported) {
                actions.reportShown()
            }
        },
    })),
])
