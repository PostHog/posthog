/** The products behind the product stars, in saved order. A star made before a rename still finds its product by href. */
export function resolveStarredProducts(
    shortcuts: FileSystemEntry[],
    candidates: FileSystemImport[]
): FileSystemImport[] {
    const seen = new Set<string>()
    return shortcuts.flatMap((shortcut) => {
        const item = candidates.find((candidate) => !!candidate.href && findProductShortcut(candidate, [shortcut]))
        if (!item?.href || seen.has(item.href)) {
            return []
        }
        seen.add(item.href)
        return [item]
    })
}

export const todayProductsLogic = kea<todayProductsLogicType>([
    path(['layout', 'today', 'todayProductsLogic']),
    connect(() => ({
        values: [
            projectTreeDataLogic,
            ['shortcutData', 'shortcutDataLoading'],
            featureFlagLogic,
            ['featureFlags'],
            teamLogic,
            ['currentTeam'],
            router,
            ['location'],
        ],
        actions: [projectTreeDataLogic, ['addShortcutItem', 'deleteShortcut']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setStarredOpen: (open: boolean) => ({ open }),
        setAllProductsOpen: (open: boolean) => ({ open }),
        toggleStarred: (item: FileSystemImport) => ({ item }),
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        // pinned: storage keys for persisted state. Renaming them resets everyone's sections.
        starredOpen: [true, { persist: true }, { setStarredOpen: (_, { open }) => open }],
        allProductsOpen: [
            inStorybook() || inStorybookTestRunner(),
            { persist: true },
            { setAllProductsOpen: (_, { open }) => open },
        ],
    }),
    selectors({
        // The same list as the Products tab of the current navigation. Home has its own rail item.
        products: [
            (s) => [s.featureFlags, s.currentTeam],
            (featureFlags: FeatureFlagsSet, currentTeam: TeamPublicType | TeamType | null): FileSystemImport[] =>
                getNavProductItems(featureFlags, currentTeam?.created_at).filter(
                    (item) => item.href !== urls.projectRoot() && !getProductAccessDisabledReason(item)
                ),
        ],
        pinnedProducts: [
            (s) => [s.products, s.search],
            (products: FileSystemImport[], search: string): FileSystemImport[] => pinnedNavProducts(products, search),
        ],
        productGroups: [
            (s) => [s.products, s.search],
            (products: FileSystemImport[], search: string): ProductsItemGroup[] => groupNavProducts(products, search),
        ],
        productCount: [
            (s) => [s.productGroups],
            (groups: ProductsItemGroup[]): number => groups.reduce((count, group) => count + group.items.length, 0),
        ],
        // Every row, starred ones too, is in the product list, so the best match there is the only active row.
        activeHref: [
            (s) => [s.location, s.products],
            (location: { pathname: string }, products: FileSystemImport[]): string | null =>
                navProductHrefForPath(removeProjectIdIfPresent(location.pathname), products),
        ],
        starredProducts: [
            (s) => [s.shortcutData, s.products, s.search],
            (shortcuts: FileSystemEntry[], products: FileSystemImport[], search: string): FileSystemImport[] =>
                resolveStarredProducts(shortcuts, products).filter((item) => productMatchesSearch(item, search)),
        ],
        starredHrefs: [
            (s) => [s.shortcutData, s.products],
            (shortcuts: FileSystemEntry[], products: FileSystemImport[]): Set<string> =>
                new Set(resolveStarredProducts(shortcuts, products).map((item) => item.href ?? '')),
        ],
    }),
    listeners(({ actions, values }) => ({
        toggleStarred: ({ item }) => {
            // The star buttons are disabled while a change saves. This also stops a repeated dispatch.
            if (values.shortcutDataLoading) {
                return
            }
            const shortcut = findProductShortcut(item, values.shortcutData)
            if (shortcut?.id) {
                actions.deleteShortcut(shortcut.id)
            } else {
                actions.addShortcutItem(item as FileSystemEntry)
            }
        },
    })),
])
