import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { router } from 'kea-router'
import type { LocationChangedPayload } from 'kea-router/lib/types'
import posthog from 'posthog-js'

import { NAV_PANEL_PLACEMENT, type NavPanelCardTeaser } from 'lib/components/NavPanelAdvertisement/navPanelAdShared'

import { TODAY_USER_PERSIST_OPTIONS } from './todayUserPersistOptions'

// Campaign ids only grow, so the list keeps the most recent ones. A card that falls off the list shows its dot again,
// which is harmless because the scheduler rotates campaigns far more slowly than this fills.
const MAX_OPENED_TEASERS = 50

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRailPromoLogicValues {
    openedTeaserIds: string[]
    promoOpen: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayRailPromoLogicActions {
    locationChanged: (payload: LocationChangedPayload) => LocationChangedPayload // router
    closePromo: () => {
        value: true
    }
    openPromo: (teaser: NavPanelCardTeaser) => {
        teaser: NavPanelCardTeaser
    }
}

export type todayRailPromoLogicType = MakeLogicType<todayRailPromoLogicValues, todayRailPromoLogicActions>

export const todayRailPromoLogic = kea<todayRailPromoLogicType>([
    path(['layout', 'today', 'todayRailPromoLogic']),
    connect(() => ({
        actions: [router, ['locationChanged']],
    })),
    actions({
        openPromo: (teaser: NavPanelCardTeaser) => ({ teaser }),
        closePromo: true,
    }),
    reducers({
        promoOpen: [
            false,
            {
                openPromo: () => true,
                closePromo: () => false,
                // A click on the card's link navigates. The popover would otherwise stay open over the new page.
                locationChanged: () => false,
            },
        ],
        openedTeaserIds: [
            [] as string[],
            TODAY_USER_PERSIST_OPTIONS,
            {
                openPromo: (ids, { teaser }) =>
                    ids.includes(teaser.id) ? ids : [...ids, teaser.id].slice(-MAX_OPENED_TEASERS),
            },
        ],
    }),
    listeners({
        openPromo: ({ teaser }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('nav panel promo opened', {
                card_type: teaser.cardType,
                card_id: teaser.id,
                placement: NAV_PANEL_PLACEMENT.RAIL,
            })
        },
    }),
])
