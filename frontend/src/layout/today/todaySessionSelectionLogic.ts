import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'
import type { LocationChangedPayload } from 'kea-router/lib/types'

import { TodayRecentSection } from './todayRecentOrder'
import {
    EMPTY_SELECTION,
    TodaySessionSelection,
    computeRangeSelection,
    orderedVisibleSessionIds,
    pruneToVisible,
    toggleSelection,
} from './todaySessionSelection'
import { TodayWorkSectionId, todaySpacesLogic } from './todaySpacesLogic'
import { TodayWorkItem } from './todayWorkItems'

function isEditableTarget(target: EventTarget | null): boolean {
    return (
        target instanceof HTMLElement &&
        (target.isContentEditable || ['INPUT', 'TEXTAREA', 'SELECT'].includes(target.tagName))
    )
}

