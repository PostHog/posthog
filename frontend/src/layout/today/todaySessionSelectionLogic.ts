export type todaySessionSelectionLogicType = MakeLogicType<
    todaySessionSelectionLogicValues,
    todaySessionSelectionLogicActions,
    Record<string, any>,
    todaySessionSelectionLogicMeta
>

export const todaySessionSelectionLogic = kea<todaySessionSelectionLogicType>([
    path(['layout', 'today', 'todaySessionSelectionLogic']),
    connect(() => ({
        values: [todaySpacesLogic, ['collapsedSections', 'pinnedItems', 'recentGroups']],
        actions: [router, ['locationChanged']],
    })),
    actions({
        setSelection: (selection: TodaySessionSelection) => ({ selection }),
        toggleSessionSelection: (sessionId: string) => ({ sessionId }),
        selectSessionRange: (sessionId: string) => ({ sessionId }),
        clearSelection: true,
    }),
    reducers({
        selection: [
            EMPTY_SELECTION,
            {
                setSelection: (_, { selection }) => selection,
                toggleSessionSelection: (state, { sessionId }) => toggleSelection(state, sessionId),
                clearSelection: () => EMPTY_SELECTION,
                locationChanged: () => EMPTY_SELECTION,
            },
        ],
    }),
    selectors({
        orderedSessionIds: [
            (s) => [s.pinnedItems, s.recentGroups, s.collapsedSections],
            (
                pinnedItems: TodayWorkItem[],
                recentGroups: TodayRecentSection[],
                collapsedSections: TodayWorkSectionId[]
            ): string[] =>
                orderedVisibleSessionIds(
                    pinnedItems,
                    recentGroups.flatMap((group) => group.items),
                    collapsedSections
                ),
        ],
        // Rows that leave the list, like archived ones or those behind a filter, drop out of the selection.
        selectedSessionIds: [
            (s) => [s.selection, s.orderedSessionIds],
            (selection: TodaySessionSelection, orderedSessionIds: string[]): string[] =>
                pruneToVisible(selection.ids, orderedSessionIds),
        ],
    }),
    listeners(({ actions, values }) => ({
        selectSessionRange: ({ sessionId }) => {
            // With no anchor yet, the range starts at the open session, as it does in Desktop.
            const { location, searchParams } = router.values
            const openId =
                location.pathname.endsWith('/ai') && typeof searchParams.task === 'string' ? searchParams.task : null
            actions.setSelection(
                computeRangeSelection(
                    values.selection.anchorId ?? openId,
                    sessionId,
                    values.orderedSessionIds,
                    values.selectedSessionIds
                )
            )
        },
    })),
    afterMount(({ actions, values, cache }) => {
        cache.disposables.add(() => {
            const onKeyDown = (event: KeyboardEvent): void => {
                if (event.key === 'Escape' && !isEditableTarget(event.target) && values.selection.ids.length) {
                    actions.clearSelection()
                }
            }
            window.addEventListener('keydown', onKeyDown)
            return () => window.removeEventListener('keydown', onKeyDown)
        }, 'clearSelectionOnEscape')
    }),
])
