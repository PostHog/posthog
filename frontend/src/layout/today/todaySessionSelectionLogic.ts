export const todaySessionSelectionLogic = kea<todaySessionSelectionLogicType>([
    path(['layout', 'today', 'todaySessionSelectionLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], todaySpacesLogic, ['collapsedSections', 'pinnedItems', 'recentGroups']],
        actions: [router, ['locationChanged'], todaySpacesLogic, ['loadPinnedTasks', 'loadRecentTasks']],
    })),
    actions({
        setSelection: (selection: TodaySessionSelection) => ({ selection }),
        toggleSessionSelection: (sessionId: string) => ({ sessionId }),
        selectSessionRange: (sessionId: string) => ({ sessionId }),
        clearSelection: true,
        pinSelected: true,
        fileSelectedTo: (spaceId: string) => ({ spaceId }),
        requestBulkArchive: true,
        openBulkArchiveConfirm: (count: number, running: number) => ({ count, running }),
        closeBulkArchiveConfirm: true,
        archiveSelected: true,
        bulkActionFinished: (failedIds: string[]) => ({ failedIds }),
        restoreSessions: (sessionIds: string[]) => ({ sessionIds }),
    }),
    reducers({
        selection: [
            EMPTY_SELECTION,
            {
                setSelection: (_, { selection }) => selection,
                toggleSessionSelection: (state, { sessionId }) => toggleSelection(state, sessionId),
                clearSelection: () => EMPTY_SELECTION,
                // Full success clears the selection; a partial one keeps only the failures, so a retry is one click.
                bulkActionFinished: (state, { failedIds }) =>
                    failedIds.length ? { ids: failedIds, anchorId: state.anchorId } : EMPTY_SELECTION,
                locationChanged: () => EMPTY_SELECTION,
            },
        ],
        bulkAction: [
            null as TodayBulkAction | null,
            {
                pinSelected: () => 'pin',
                fileSelectedTo: () => 'file',
                archiveSelected: () => 'archive',
                bulkActionFinished: () => null,
            },
        ],
        bulkArchiveConfirm: [
            CLOSED_CONFIRM,
            {
                openBulkArchiveConfirm: (_, { count, running }) => ({ open: true, count, running }),
                closeBulkArchiveConfirm: (state) => ({ ...state, open: false }),
                bulkActionFinished: (state) => ({ ...state, open: false }),
            },
        ],
    }),
    selectors({
        orderedSessionIds: [
            (s) => [s.pinnedItems, s.recentGroups, s.collapsedSections],
            (
                pinnedItems: TodayWorkItem[],
                recentGroups: TodayRecentSection[],
                collapsedSections: TodayWorkSectionId[]
            ): string[] =>
                orderedVisibleSessionIds(
                    pinnedItems,
                    recentGroups.flatMap((group) => group.items),
                    collapsedSections
                ),
        ],
        // Rows that leave the list, like archived ones or those behind a filter, drop out of the selection.
        selectedSessionIds: [
            (s) => [s.selection, s.orderedSessionIds],
            (selection: TodaySessionSelection, orderedSessionIds: string[]): string[] =>
                pruneToVisible(selection.ids, orderedSessionIds),
        ],
        selectedSessions: [
            (s) => [s.selectedSessionIds, s.pinnedItems, s.recentGroups],
            (
                selectedSessionIds: string[],
                pinnedItems: TodayWorkItem[],
                recentGroups: TodayRecentSection[]
            ): TodayWorkItem[] => {
                const items = new Map(
                    [...pinnedItems, ...recentGroups.flatMap((group) => group.items)].map((item) => [item.id, item])
                )
                return selectedSessionIds.flatMap((id) => items.get(id) ?? [])
            },
        ],
        bulkPinDirection: [
            (s) => [s.selectedSessionIds, s.pinnedItems],
            (selectedSessionIds: string[], pinnedItems: TodayWorkItem[]): 'pin' | 'unpin' =>
                computeBulkPinDirection(selectedSessionIds, new Set(pinnedItems.map((item) => item.id))),
        ],
        runningSelectedCount: [
            (s) => [s.selectedSessions],
            (selectedSessions: TodayWorkItem[]): number =>
                selectedSessions.filter((item) => activeCloudRunId(item) !== null).length,
        ],
    }),
    listeners(({ actions, values }) => ({
        selectSessionRange: ({ sessionId }) => {
            // With no anchor yet, the range starts at the open session, as it does in Desktop.
            const { location, searchParams } = router.values
            const openId =
                location.pathname.endsWith('/ai') && typeof searchParams.task === 'string' ? searchParams.task : null
            actions.setSelection(
                computeRangeSelection(
                    values.selection.anchorId ?? openId,
                    sessionId,
                    values.orderedSessionIds,
                    values.selectedSessionIds
                )
            )
        },
    })),
    listeners(({ actions, values }) => {
        const teamId = (): string => String(values.currentTeamId)

        /** One request per session, like Desktop, since there is no bulk endpoint. Returns the ids that failed. */
        const runEach = async (ids: string[], request: (id: string) => Promise<unknown>): Promise<string[]> => {
            const results = await Promise.allSettled(ids.map(request))
            return ids.filter((_, index) => results[index].status === 'rejected')
        }

        const report = (verb: TodayBulkVerb, total: number, failed: number, onUndo?: () => void): void => {
            const result = bulkResultToast(verb, total - failed, failed)
            const action = onUndo && total > failed ? { label: 'Undo', onClick: onUndo } : undefined
            if (result.kind === 'success') {
                toast.success({ title: result.title, action })
            } else {
                toast.error({ title: result.title, description: result.description, action })
            }
        }

        const finish = (failedIds: string[]): void => {
            actions.bulkActionFinished(failedIds)
            actions.loadPinnedTasks()
            actions.loadRecentTasks()
        }

        return {
            pinSelected: async () => {
                const ids = values.selectedSessionIds
                const pinned = values.bulkPinDirection === 'pin'
                const failed = await runEach(ids, (id) => tasksPinCreate(teamId(), id, { pinned }))
                report(pinned ? 'pin' : 'unpin', ids.length, failed.length)
                finish(failed)
            },
            fileSelectedTo: async ({ spaceId }) => {
                const ids = values.selectedSessionIds
                const failed = await runEach(ids, (id) => tasksPartialUpdate(teamId(), id, { channel: spaceId }))
                report('file', ids.length, failed.length)
                finish(failed)
            },
            requestBulkArchive: () => {
                if (values.runningSelectedCount > 0) {
                    actions.openBulkArchiveConfirm(values.selectedSessionIds.length, values.runningSelectedCount)
                } else {
                    actions.archiveSelected()
                }
            },
            archiveSelected: async () => {
                const runIds = new Map(values.selectedSessions.map((item) => [item.id, activeCloudRunId(item)]))
                const ids = [...runIds.keys()]
                const failed = await runEach(ids, async (id) => {
                    const runId = runIds.get(id)
                    // Archiving alone leaves the cloud run going, so stop it first, as the confirm says.
                    if (runId) {
                        await tasksRunsCancelCreate(teamId(), id, runId)
                    }
                    await tasksPartialUpdate(teamId(), id, { archived: true })
                })
                const archivedIds = ids.filter((id) => !failed.includes(id))
                report('archive', ids.length, failed.length, () => actions.restoreSessions(archivedIds))
                finish(failed)
            },
            restoreSessions: async ({ sessionIds }) => {
                const failed = await runEach(sessionIds, (id) => tasksPartialUpdate(teamId(), id, { archived: false }))
                if (failed.length) {
                    report('restore', sessionIds.length, failed.length)
                }
                actions.loadPinnedTasks()
                actions.loadRecentTasks()
            },
        }
    }),
    afterMount(({ actions, values, cache }) => {
        cache.disposables.add(() => {
            const onKeyDown = (event: KeyboardEvent): void => {
                // The archive confirm answers Escape itself, and the selection it names has to stay.
                if (
                    event.key === 'Escape' &&
                    !isEditableTarget(event.target) &&
                    !values.bulkArchiveConfirm.open &&
                    values.selection.ids.length
                ) {
                    actions.clearSelection()
                }
            }
            window.addEventListener('keydown', onKeyDown)
            return () => window.removeEventListener('keydown', onKeyDown)
        }, 'clearSelectionOnEscape')
    }),
])
