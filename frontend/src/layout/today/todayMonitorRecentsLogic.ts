import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'
import { subscriptions } from 'kea-subscriptions'

import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { objectsEqual } from 'lib/utils/objects'
import { sceneLogic } from 'scenes/sceneLogic'

import { TODAY_MONITOR_RECENT_KEY, TodayMonitorRecent, monitorAreaEnabled } from './todayMonitor'
import { newestByName } from './todayNewestByName'
import { TODAY_USER_PERSIST_OPTIONS } from './todayUserPersistOptions'

export const TODAY_MONITOR_RECENTS_LIMIT = 10

/** Puts a visit first. Reloading the same page changes nothing, so the list stays stable while a page loads. */
export function addMonitorRecent(recents: TodayMonitorRecent[], recent: TodayMonitorRecent): TodayMonitorRecent[] {
    const [first] = recents
    if (first?.href === recent.href && first.name === recent.name) {
        return recents
    }
    return [recent, ...recents.filter((item) => item.href !== recent.href)].slice(0, TODAY_MONITOR_RECENTS_LIMIT)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayMonitorRecentsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentRecent: TodayMonitorRecent | null
    recentRows: TodayMonitorRecent[]
    recents: TodayMonitorRecent[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayMonitorRecentsLogicActions {
    addRecent: (recent: TodayMonitorRecent) => {
        recent: TodayMonitorRecent
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayMonitorRecentsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        currentRecent: (featureFlags: FeatureFlagsSet, arg: TodayMonitorRecent | null) => TodayMonitorRecent | null
        recentRows: (recents: TodayMonitorRecent[]) => TodayMonitorRecent[]
    }
}

export type todayMonitorRecentsLogicType = MakeLogicType<
    todayMonitorRecentsLogicValues,
    todayMonitorRecentsLogicActions,
    Record<string, any>,
    todayMonitorRecentsLogicMeta
>

/** Mounted by `TodayShell`, so an issue opened from any pane counts. */
export const todayMonitorRecentsLogic = kea<todayMonitorRecentsLogicType>([
    path(['layout', 'today', 'todayMonitorRecentsLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
        logic: [sceneLogic],
    })),
    actions({
        addRecent: (recent: TodayMonitorRecent) => ({ recent }),
    }),
    reducers({
        // pinned: storage key for the saved Recents list. Renaming it empties everyone's Monitor Recents.
        recents: [
            [] as TodayMonitorRecent[],
            TODAY_USER_PERSIST_OPTIONS,
            {
                addRecent: (state, { recent }) => addMonitorRecent(state, recent),
            },
        ],
    }),
    selectors({
        currentRecent: [
            (s) => [
                s.featureFlags,
                (state, props): TodayMonitorRecent | null => {
                    const activeSceneLogic = sceneLogic.selectors.activeSceneLogic(state, props)
                    if (!activeSceneLogic || !(TODAY_MONITOR_RECENT_KEY in activeSceneLogic.selectors)) {
                        return null
                    }
                    const activeLoadedScene = sceneLogic.selectors.activeLoadedScene(state, props)
                    try {
                        return activeSceneLogic.selectors[TODAY_MONITOR_RECENT_KEY](
                            state,
                            activeLoadedScene?.paramsToProps?.(activeLoadedScene?.sceneParams) || props
                        )
                    } catch {
                        return null
                    }
                },
            ],
            (featureFlags: FeatureFlagsSet, recent: TodayMonitorRecent | null): TodayMonitorRecent | null =>
                monitorAreaEnabled(featureFlags) ? recent : null,
            { resultEqualityCheck: objectsEqual },
        ],
        recentRows: [
            (s) => [s.recents],
            (recents: TodayMonitorRecent[]): TodayMonitorRecent[] =>
                newestByName(
                    recents,
                    (item) => item.name,
                    (item) => item.href,
                    TODAY_MONITOR_RECENTS_LIMIT
                ),
        ],
    }),
    subscriptions(({ actions }) => ({
        currentRecent: (recent: TodayMonitorRecent | null) => {
            if (recent) {
                actions.addRecent(recent)
            }
        },
    })),
])
