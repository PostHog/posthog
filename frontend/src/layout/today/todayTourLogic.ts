export function tourStepsForFlags(featureFlags: FeatureFlagsSet): TodayTourStep[] {
    return TODAY_TOUR_STEPS.filter((step) => isTodayPaneEnabled(step.pane, featureFlags))
}

/** A running tour. */
export interface TodayTourSession {
    /** Fixed when the tour starts, so a flag that loads mid-tour can't move the person to another step. */
    steps: TodayTourStep[]
    stepIndex: number
    /** Where the cursor starts: the pointer that clicked "Take tour". */
    origin: TodayTourPoint
    /** The view to go back to when the tour ends. */
    returnTo: TodayView
    /** Where the cursor stopped for the current step. The card shows next to it, so there is no card until then. */
    anchor: TodayTourPoint | null
}

