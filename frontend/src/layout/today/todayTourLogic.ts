export type todayTourLogicType = MakeLogicType<
    todayTourLogicValues,
    todayTourLogicActions,
    Record<string, any>,
    todayTourLogicMeta
>

/**
 * Walks through the main rail panes and the switch back in the "More" menu, then returns to the view the tour
 * started from. `TodayTourCursor` moves between the steps: it calls `clickTourTarget` when it clicks, and
 * `revealTourStep` with the point it stopped at, which is where the card shows.
 */
export const todayTourLogic = kea<todayTourLogicType>([
    path(['layout', 'today', 'todayTourLogic']),
    connect(() => ({
        values: [todayShellLogic, ['currentView']],
        actions: [
            todayShellLogic,
            ['showPane', 'restoreView'],
            navSwitchLogic,
            ['setNewNavDialogOpen', 'dismissNewNavDialog', 'showAdvertisement'],
            helpMenuLogic,
            ['setHelpMenuOpen'],
        ],
    })),
    actions({
        startTour: (origin: TodayTourPoint) => ({ origin }),
        setTour: (tour: TodayTourSession | null) => ({ tour }),
        nextTourStep: true,
        clickTourTarget: true,
        revealTourStep: (anchor: TodayTourPoint) => ({ anchor }),
        endTour: true,
        markTourCompleted: true,
        resetDesignTour: true,
    }),
    reducers({
        tour: [
            null as TodayTourSession | null,
            {
                setTour: (_, { tour }) => tour,
                revealTourStep: (tour, { anchor }) => tour && { ...tour, anchor },
            },
        ],
        // Someone who saw every step gets "I'll try it out" in place of "Take tour" whenever the dialog shows again.
        // It is persisted because this logic unmounts while the old navigation shows, and a reload clears it too.
        tourCompleted: [
            false,
            { persist: true },
            {
                markTourCompleted: () => true,
                resetDesignTour: () => false,
            },
        ],
        // The dialog that opens when the tour ends congratulates someone who saw every step. Once that dialog closes,
        // a later dialog shows its usual copy, so this is not persisted.
        tourJustCompleted: [
            false,
            {
                markTourCompleted: () => true,
                setNewNavDialogOpen: (state, { open }) => open && state,
                dismissNewNavDialog: () => false,
                resetDesignTour: () => false,
            },
        ],
    }),
    selectors({
        tourActive: [(s) => [s.tour], (tour: TodayTourSession | null): boolean => tour !== null],
        tourStep: [
            (s) => [s.tour],
            (tour: TodayTourSession | null): TodayTourStep | null =>
                tour ? (TODAY_TOUR_STEPS[tour.stepIndex] ?? null) : null,
        ],
    }),
    listeners(({ actions, values }) => ({
        startTour: ({ origin }) => {
            // pinned: analytics event name.
            posthog.capture('today nav tour started')
            actions.setNewNavDialogOpen(false)
            actions.setTour({ stepIndex: 0, origin, returnTo: values.currentView, anchor: null })
        },
        nextTourStep: () => {
            // A card's exit animation can finish after the tour ended, so a late Next must not start a new one.
            const { tour } = values
            if (!tour) {
                return
            }
            if (tour.stepIndex + 1 < TODAY_TOUR_STEPS.length) {
                actions.setTour({ ...tour, stepIndex: tour.stepIndex + 1, anchor: null })
            } else {
                actions.endTour()
            }
        },
        clickTourTarget: () => {
            const step = values.tourStep
            if (step?.kind === 'switch') {
                actions.setHelpMenuOpen(true)
            } else if (step?.kind === 'pane') {
                actions.showPane(step.pane)
            }
        },
        endTour: () => {
            const { tour } = values
            if (!tour) {
                return
            }
            const completed = tour.stepIndex === TODAY_TOUR_STEPS.length - 1
            // pinned: analytics event name and properties.
            posthog.capture('today nav tour ended', { step: tour.stepIndex, completed })
            if (completed) {
                actions.markTourCompleted()
            }
            actions.setTour(null)
            // Only the last step opens the "More" menu. Closing a closed menu changes nothing.
            actions.setHelpMenuOpen(false)
            actions.restoreView(tour.returnTo)
            actions.setNewNavDialogOpen(true)
        },
        // A local development shortcut that forgets what the switch flow saved in this browser, then reloads, so the
        // flow runs again from the start. The reload also drops logics that a hot reload left on an older version.
        resetDesignTour: () => {
            actions.showAdvertisement()
            window.location.reload()
        },
    })),
])
