import { MakeLogicType, afterMount, kea, key, listeners, path, props, propsChanged } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'

import { splitPath } from '~/layout/panel-layout/ProjectTree/utils'
import { FileSystemEntry } from '~/queries/schema/schema-general'

export interface SceneTitleSameNameLogicProps {
    /** File system type of the item, e.g. `dashboard` or `insight` */
    type: string
    /** File system ref of the item, used to leave the item itself out of the results */
    itemRef: string
    name: string
}

const SAME_NAME_SEARCH_LIMIT = 100

function normalizeName(name: string): string {
    return name.trim().toLowerCase()
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneTitleSameNameLogicValues {
    sameNameItems: FileSystemEntry[]
    sameNameItemsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneTitleSameNameLogicActions {
    loadSameNameItems: () => any
    loadSameNameItemsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSameNameItemsSuccess: (
        sameNameItems: FileSystemEntry[],
        payload?: any
    ) => {
        sameNameItems: FileSystemEntry[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneTitleSameNameLogicMeta {
    key: string
}

export type sceneTitleSameNameLogicType = MakeLogicType<
    sceneTitleSameNameLogicValues,
    sceneTitleSameNameLogicActions,
    SceneTitleSameNameLogicProps,
    sceneTitleSameNameLogicMeta
>

export const sceneTitleSameNameLogic = kea<sceneTitleSameNameLogicType>([
    path((key) => ['layout', 'scenes', 'components', 'sceneTitleSameNameLogic', key]),
    props({} as SceneTitleSameNameLogicProps),
    key((props) => `${props.type}/${props.itemRef}`),
    loaders(({ props }) => ({
        sameNameItems: [
            [] as FileSystemEntry[],
            {
                loadSameNameItems: async (_, breakpoint) => {
                    const name = normalizeName(props.name)
                    if (!name) {
                        return []
                    }
                    await breakpoint(300)
                    let results: FileSystemEntry[]
                    try {
                        // The search matches the name as a substring, so keep only exact matches
                        const response = await api.fileSystem.list({
                            type: props.type,
                            search: props.name,
                            searchNameOnly: true,
                            limit: SAME_NAME_SEARCH_LIMIT,
                        })
                        results = response.results
                    } catch {
                        // A hint is not worth an error toast
                        return []
                    }
                    breakpoint()
                    return results.filter(
                        (entry) =>
                            entry.ref !== props.itemRef &&
                            !!entry.href &&
                            normalizeName(splitPath(entry.path).pop() ?? '') === name
                    )
                },
            },
        ],
    })),
    listeners(({ props }) => ({
        loadSameNameItemsSuccess: ({ sameNameItems }) => {
            if (sameNameItems.length > 0) {
                posthog.capture('scene title same name warning shown', {
                    type: props.type,
                    same_name_count: sameNameItems.length,
                })
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadSameNameItems()
    }),
    propsChanged(({ actions, props }, oldProps) => {
        if (normalizeName(props.name) !== normalizeName(oldProps.name)) {
            actions.loadSameNameItems()
        }
    }),
])
