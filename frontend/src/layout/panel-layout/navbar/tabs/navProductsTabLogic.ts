export const navProductsTabLogic = kea<navProductsTabLogicType>([
    path(['layout', 'panel-layout', 'navbar', 'tabs', 'navProductsTabLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            preflightLogic,
            ['preflight'],
            featureFlagLogic,
            ['featureFlags'],
            aiConsentLogic,
            ['dataProcessingAccepted'],
            projectTreeDataLogic,
            ['shortcutData', 'shortcutDataHasLoaded', 'shortcutDataLoading'],
        ],
        actions: [
            projectTreeDataLogic,
            ['deleteShortcutSuccess', 'loadShortcutsFailure', 'loadShortcutsSuccess'],
            teamLogic,
            ['loadCurrentTeamSuccess'],
        ],
        logic: [projectTreeLogic({ key: PRODUCTS_STARRED_TREE_KEY, root: 'shortcuts://', shortcutScope: 'products' })],
    })),
    actions({
        resetAppConfiguration: true,
        setSearch: (search: string) => ({ search }),
        setAppRecommendationQuery: (query: string) => ({ query }),
        queueAppStar: (productPath: string, starred: boolean) => ({ productPath, starred }),
        finishAppStar: (productPath: string, starred: boolean) => ({ productPath, starred }),
        setStarSaveError: (error: string | null) => ({ error }),
        setAppRankingError: (error: string | null) => ({ error }),
        setCustomizeSidebarOpen: (open: boolean) => ({ open }),
        setAllProductsOpen: (open: boolean) => ({ open }),
        setProductStarred: (productPath: string, starred: boolean) => ({ productPath, starred }),
    }),
    loaders(({ actions, values, cache }) => ({
        starSaveResult: [
            null as null,
            {
                saveAppStars: async (_: void, breakpoint) => {
                    const teamId = values.currentTeamId
                    while (Object.keys(values.pendingAppStars).length > 0) {
                        const [productPath, starred] = Object.entries(values.pendingAppStars)[0]
                        const item = values.configurableProducts.find((app) => app.path === productPath)
                        const shortcutId = values.starredProductIds[productPath]
                        try {
                            if (!item || teamId === null) {
                                actions.setStarSaveError(
                                    'Some changes could not be saved. Toggle those apps again to retry.'
                                )
                            } else {
                                const shortcutPath = joinPath(splitPath(item.path).slice(-1))
                                if (starred && !shortcutId) {
                                    const entry = await coreApi.fileSystemShortcutCreate(String(teamId), {
                                        path: shortcutPath,
                                        type: item.iconType || item.type,
                                        href: item.href,
                                    })
                                    breakpoint()
                                    actions.loadShortcutsSuccess([
                                        ...values.shortcutData,
                                        {
                                            id: entry.id,
                                            path: entry.path,
                                            type: entry.type,
                                            href: entry.href ?? undefined,
                                        },
                                    ])
                                    posthog.capture('navbar starred item added', {
                                        item_type: item.iconType || item.type || 'unknown',
                                        item_name: shortcutPath,
                                    })
                                } else if (!starred && shortcutId) {
                                    await coreApi.fileSystemShortcutDestroy(String(teamId), shortcutId)
                                    breakpoint()
                                    actions.loadShortcutsSuccess(
                                        values.shortcutData.filter((entry) => entry.id !== shortcutId)
                                    )
                                    posthog.capture('navbar starred item removed', {
                                        item_type: item.iconType || item.type || 'unknown',
                                        item_name: shortcutPath,
                                    })
                                }
                            }
                        } catch {
                            breakpoint()
                            actions.setStarSaveError(
                                'Some changes could not be saved. Toggle those apps again to retry.'
                            )
                        }
                        actions.finishAppStar(productPath, starred)
                    }
                    return null
                },
            },
        ],
        appRankings: [
            null as Record<string, number> | null,
            {
                rankApps: async ({ query }: { query: string }, breakpoint) => {
                    cache.disposables.dispose('appRankingRequest')
                    actions.setAppRankingError(null)
                    if (!query.trim() || !values.appRecommendationsEnabled || values.currentTeamId === null) {
                        return null
                    }
                    await breakpoint(500)
                    if (!values.appRecommendationsEnabled) {
                        return null
                    }
                    const items = values.configurableProducts
                    const rankingCache: Map<string, Record<string, number>> = (cache.appRankingCache ??= new Map())
                    const cacheKey = JSON.stringify([
                        values.currentTeamId,
                        query.trim(),
                        items.map((item) => item.path),
                    ])
                    const cachedRankings = rankingCache.get(cacheKey)
                    if (cachedRankings) {
                        return cachedRankings
                    }
                    const controller = new AbortController()
                    cache.disposables.add(() => () => controller.abort(), 'appRankingRequest', {
                        pauseOnPageHidden: false,
                    })
                    try {
                        const scores = await Promise.all(
                            buildAppRankingQuestions(items).map(async (questions) => {
                                const result = await withTimeout(
                                    decisionsApi.mlInferenceDecisionsDecideCreate(
                                        String(values.currentTeamId),
                                        {
                                            state: query.trim(),
                                            questions,
                                        },
                                        { signal: controller.signal }
                                    ),
                                    10000
                                )
                                return readAppRankings(result, items)
                            })
                        )
                        breakpoint()
                        if (!values.appRecommendationsEnabled) {
                            return null
                        }
                        const rankings = Object.assign({}, ...scores)
                        rankingCache.set(cacheKey, rankings)
                        if (rankingCache.size > 10) {
                            rankingCache.delete(rankingCache.keys().next().value!)
                        }
                        return rankings
                    } catch {
                        breakpoint()
                        actions.setAppRankingError(
                            'Jev could not suggest apps. Edit your description to try again, or choose from all apps below.'
                        )
                        return null
                    } finally {
                        controller.abort()
                    }
                },
            },
        ],
    })),
    reducers({
        appRankings: [null as Record<string, number> | null, { setAppRecommendationQuery: () => null }],
        appRecommendationQuery: ['', { setAppRecommendationQuery: (_, { query }) => query }],
        appRankingError: [null as string | null, { setAppRankingError: (_, { error }) => error }],
        starSaveError: [
            null as string | null,
            {
                setStarSaveError: (_, { error }) => error,
                queueAppStar: () => null,
                resetAppConfiguration: () => null,
            },
        ],
        pendingAppStars: [
            {} as Record<string, boolean>,
            {
                resetAppConfiguration: () => ({}),
                queueAppStar: (state, { productPath, starred }) => ({ ...state, [productPath]: starred }),
                finishAppStar: (state, { productPath, starred }) => {
                    if (state[productPath] !== starred) {
                        return state
                    }
                    const remaining = { ...state }
                    delete remaining[productPath]
                    return remaining
                },
            },
        ],
        search: ['', { setSearch: (_, { search }) => search }],
        customizeSidebarOpen: [
            false,
            { setCustomizeSidebarOpen: (_, { open }) => open, resetAppConfiguration: () => false },
        ],
        // pinned: persisted under this logic's path, so renaming the reducer resets everyone's choice.
        // Storybook starts open so visual snapshots cover the full list.
        allProductsOpen: [
            inStorybook() || inStorybookTestRunner(),
            { persist: true },
            { setAllProductsOpen: (_, { open }) => open },
        ],
    }),
    selectors({
        appRecommendationsEnabled: [
            (s) => [s.featureFlags, s.preflight, s.dataProcessingAccepted],
            (
                featureFlags: FeatureFlagsSet,
                preflight: PreflightStatus | null,
                dataProcessingAccepted: boolean
            ): boolean =>
                dataProcessingAccepted && !!(preflight?.is_debug || featureFlags[FEATURE_FLAGS.ML_INFERENCE_DECISIONS]),
        ],
        rankedConfigurableApps: [
            (s) => [s.configurableProducts, s.appRankings, s.appRecommendationQuery, s.appRecommendationsEnabled],
            (
                items: FileSystemImport[],
                rankings: Record<string, number> | null,
                query: string,
                enabled: boolean
            ): FileSystemImport[] =>
                enabled && query.trim() && rankings
                    ? [...items].sort((a, b) => (rankings[b.path] ?? 0) - (rankings[a.path] ?? 0))
                    : items,
        ],
        appMatchGroups: [
            (s) => [s.rankedConfigurableApps, s.appRankings, s.appRecommendationQuery, s.appRecommendationsEnabled],
            (
                items: FileSystemImport[],
                rankings: Record<string, number> | null,
                query: string,
                enabled: boolean
            ): AppMatchGroups | null =>
                enabled && query.trim() && rankings
                    ? {
                          matching: items.filter((item) => (rankings[item.path] ?? 0) >= APP_MATCH_THRESHOLD),
                          other: items.filter((item) => (rankings[item.path] ?? 0) < APP_MATCH_THRESHOLD),
                      }
                    : null,
        ],
        selectedAppStars: [
            (s) => [s.starredProductIds, s.pendingAppStars],
            (ids: Record<string, string>, pending: Record<string, boolean>): Record<string, boolean> => ({
                ...Object.fromEntries(Object.keys(ids).map((path) => [path, true])),
                ...pending,
            }),
        ],
        allItems: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): FileSystemImport[] => {
                const items: FileSystemImport[] = [
                    {
                        path: 'Home',
                        category: PINNED_CATEGORY,
                        iconType: 'home',
                        href: urls.projectRoot(),
                        visualOrder: 0,
                    },
                    {
                        path: 'Activity',
                        displayLabel: 'Activity and people',
                        category: PINNED_CATEGORY,
                        iconType: 'activity',
                        href: urls.activity(ActivityTab.ExploreEvents),
                        visualOrder: 2,
                    },
                    ...getDefaultTreeProducts().map(
                        (item): FileSystemImport =>
                            item.href === urls.inbox()
                                ? {
                                      ...item,
                                      displayLabel: 'Self-driving',
                                      category: PINNED_CATEGORY,
                                      visualOrder: 1,
                                      tags: ['beta'],
                                  }
                                : item
                    ),
                    // Persons, cohorts and groups are tabs of the Activity and people scene, so they are not listed here.
                    ...getDefaultTreeData(),
                ]
                const destinations = new Map<string, FileSystemImport>()
                for (const item of items) {
                    if (
                        !item.href ||
                        DEFINITIONS_TAB_HREFS.has(item.href) ||
                        (item.flag && !featureFlags[item.flag as keyof FeatureFlagsSet])
                    ) {
                        continue
                    }
                    const existing = destinations.get(item.href)
                    destinations.set(item.href, existing ? { ...item, ...existing } : item)
                }
                return [...destinations.values()].map((item) =>
                    POPULAR_PRODUCT_PATHS.includes(item.path) ? { ...item, category: POPULAR_CATEGORY } : item
                )
            },
        ],
        pinnedItems: [
            (s) => [s.allItems, s.search],
            (items: FileSystemImport[], search: string): FileSystemImport[] =>
                items
                    .filter((item) => item.category === PINNED_CATEGORY && productMatchesSearch(item, search))
                    .sort((a, b) => (a.visualOrder ?? Infinity) - (b.visualOrder ?? Infinity)),
        ],
        groupedItems: [
            (s) => [s.allItems, s.search],
            (items: FileSystemImport[], search: string): ProductsItemGroup[] =>
                groupProducts(
                    items.filter((item) => item.category !== PINNED_CATEGORY),
                    search
                ),
        ],
        configurableProducts: [
            (s) => [s.allItems],
            (items: FileSystemImport[]): FileSystemImport[] =>
                items
                    .filter((item) => item.category !== PINNED_CATEGORY && !getProductAccessDisabledReason(item))
                    .sort((a, b) => productsItemName(a).localeCompare(productsItemName(b))),
        ],
        starredProductIds: [
            (s) => [s.allItems, s.shortcutData],
            (items: FileSystemImport[], shortcuts: FileSystemEntry[]): Record<string, string> => {
                const ids: Record<string, string> = {}
                for (const item of items) {
                    const shortcut = findProductShortcut(item, shortcuts)
                    if (shortcut) {
                        ids[item.path] = shortcut.id
                    }
                }
                return ids
            },
        ],
        // Only a sidebar with starred products has something to show above the list, so only then can it close.
        allProductsCollapsible: [
            (s) => [s.shortcutDataHasLoaded, s.starredProductIds],
            (shortcutDataHasLoaded: boolean, starredProductIds: Record<string, string>): boolean =>
                shortcutDataHasLoaded && Object.keys(starredProductIds).length > 0,
        ],
        // A search always shows its matches, even when the list is closed.
        allProductsVisible: [
            (s) => [s.allProductsOpen, s.allProductsCollapsible, s.search, s.shortcutDataHasLoaded],
            (
                allProductsOpen: boolean,
                allProductsCollapsible: boolean,
                search: string,
                shortcutDataHasLoaded: boolean
            ): boolean => allProductsOpen || !!search.trim() || (shortcutDataHasLoaded && !allProductsCollapsible),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        // A sidebar shown open because nothing was starred stays open after the first star.
        const keepAllProductsOpenWithoutStars = (): void => {
            if (values.shortcutDataHasLoaded && !values.allProductsCollapsible && !values.allProductsOpen) {
                actions.setAllProductsOpen(true)
            }
        }
        return {
            loadShortcutsSuccess: keepAllProductsOpenWithoutStars,
            loadShortcutsFailure: keepAllProductsOpenWithoutStars,
            deleteShortcutSuccess: keepAllProductsOpenWithoutStars,
            loadCurrentTeamSuccess: () => {
                if (cache.appConfigurationTeamId !== values.currentTeamId) {
                    cache.appConfigurationTeamId = values.currentTeamId
                    const hadPendingChanges = Object.keys(values.pendingAppStars).length > 0
                    actions.resetAppConfiguration()
                    if (hadPendingChanges) {
                        lemonToast.error(
                            'Your project changed before all starred apps were saved. Return to the previous project to review your starred apps.',
                            { toastId: 'configure-starred-project-changed', autoClose: false }
                        )
                    }
                }
            },
            resetAppConfiguration: () => {
                actions.setAppRecommendationQuery('')
                actions.saveAppStars()
            },
            setStarSaveError: ({ error }) => {
                if (error && !values.customizeSidebarOpen) {
                    lemonToast.error(error, {
                        toastId: 'configure-starred-save-error',
                        autoClose: false,
                        button: { label: 'Customize sidebar', action: () => actions.setCustomizeSidebarOpen(true) },
                    })
                }
            },
            setCustomizeSidebarOpen: ({ open }) => {
                if (!open && values.starSaveError) {
                    actions.setStarSaveError(values.starSaveError)
                }
            },
            setAppRecommendationQuery: ({ query }) => actions.rankApps({ query }),
            setProductStarred: ({ productPath, starred }) => {
                if (!values.configurableProducts.some((app) => app.path === productPath)) {
                    return
                }
                actions.queueAppStar(productPath, starred)
            },
            queueAppStar: async (_, breakpoint) => {
                await breakpoint(250)
                if (!values.starSaveResultLoading) {
                    actions.saveAppStars()
                }
            },
            setSearch: ({ search }) => {
                projectTreeLogic({
                    key: PRODUCTS_STARRED_TREE_KEY,
                    root: 'shortcuts://',
                    shortcutScope: 'products',
                }).actions.setSearchTerm(search)
            },
        }
    }),
    afterMount(({ cache, values }) => {
        cache.appConfigurationTeamId = values.currentTeamId
    }),
])
