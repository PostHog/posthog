export const navProductsTabLogic = kea<navProductsTabLogicType>([
    path(['layout', 'panel-layout', 'navbar', 'tabs', 'navProductsTabLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId', 'currentTeam'],
            preflightLogic,
            ['preflight'],
            featureFlagLogic,
            ['featureFlags'],
            aiConsentLogic,
            ['dataProcessingAccepted'],
            projectTreeDataLogic,
            ['shortcutData', 'shortcutDataHasLoaded', 'shortcutDataLoading'],
        ],
        actions: [
            projectTreeDataLogic,
            ['deleteShortcutSuccess', 'loadShortcuts', 'loadShortcutsFailure', 'loadShortcutsSuccess'],
            router,
            ['locationChanged'],
            teamLogic,
            ['loadCurrentTeamSuccess'],
        ],
        logic: [projectTreeLogic({ key: PRODUCTS_STARRED_TREE_KEY, root: 'shortcuts://', shortcutScope: 'products' })],
    })),
    actions({
        resetAppConfiguration: true,
        setSearch: (search: string) => ({ search }),
        setAppRecommendationQuery: (query: string) => ({ query }),
        setAppRankingError: (error: string | null) => ({ error }),
        setCustomizeSidebarOpen: (open: boolean) => ({ open }),
        setAllProductsOpen: (open: boolean) => ({ open }),
        revealAllProductsForFind: true,
        setDraftStarred: (productPath: string, starred: boolean) => ({ productPath, starred }),
        unselectAllStarred: true,
        setCustomizeSearch: (search: string) => ({ search }),
        saveStarredProducts: true,
        saveStarredProductsSuccess: true,
        saveStarredProductsFailure: true,
    }),
    loaders(({ actions, values, cache }) => ({
        appRankings: [
            null as Record<string, number> | null,
            {
                rankApps: async ({ query }: { query: string }, breakpoint) => {
                    cache.disposables.dispose('appRankingRequest')
                    actions.setAppRankingError(null)
                    if (!query.trim() || !values.appRecommendationsEnabled || values.currentTeamId === null) {
                        return null
                    }
                    await breakpoint(500)
                    if (!values.appRecommendationsEnabled) {
                        return null
                    }
                    const items = values.configurableProducts
                    const rankingCache: Map<string, Record<string, number>> = (cache.appRankingCache ??= new Map())
                    const cacheKey = JSON.stringify([
                        values.currentTeamId,
                        query.trim(),
                        items.map((item) => item.path),
                    ])
                    const cachedRankings = rankingCache.get(cacheKey)
                    if (cachedRankings) {
                        return cachedRankings
                    }
                    const controller = new AbortController()
                    cache.disposables.add(() => () => controller.abort(), 'appRankingRequest', {
                        pauseOnPageHidden: false,
                    })
                    try {
                        const scores = await Promise.all(
                            buildAppRankingQuestions(items).map(async (questions) => {
                                const result = await withTimeout(
                                    decisionsApi.mlInferenceDecisionsDecideCreate(
                                        String(values.currentTeamId),
                                        {
                                            state: query.trim(),
                                            questions,
                                        },
                                        { signal: controller.signal }
                                    ),
                                    10000
                                )
                                return readAppRankings(result, items)
                            })
                        )
                        breakpoint()
                        if (!values.appRecommendationsEnabled) {
                            return null
                        }
                        const rankings = Object.assign({}, ...scores)
                        rankingCache.set(cacheKey, rankings)
                        if (rankingCache.size > 10) {
                            rankingCache.delete(rankingCache.keys().next().value!)
                        }
                        return rankings
                    } catch {
                        breakpoint()
                        actions.setAppRankingError(
                            'Jev could not suggest apps. Edit your description to try again, or choose from all apps below.'
                        )
                        return null
                    } finally {
                        controller.abort()
                    }
                },
            },
        ],
    })),
    reducers({
        appRankings: [null as Record<string, number> | null, { setAppRecommendationQuery: () => null }],
        appRecommendationQuery: ['', { setAppRecommendationQuery: (_, { query }) => query }],
        appRankingError: [null as string | null, { setAppRankingError: (_, { error }) => error }],
        search: ['', { setSearch: (_, { search }) => search }],
        customizeSidebarOpen: [
            false,
            {
                setCustomizeSidebarOpen: (_, { open }) => open,
                saveStarredProductsSuccess: () => false,
                resetAppConfiguration: () => false,
            },
        ],
        // Choices made in the dialog, applied over the starting selection. Nothing is saved until Save.
        draftStarredChanges: [
            {} as Record<string, boolean>,
            {
                setDraftStarred: (state, { productPath, starred }) => ({ ...state, [productPath]: starred }),
                unselectAllStarred: () => ({}),
                setCustomizeSidebarOpen: (state, { open }) => (open ? {} : state),
            },
        ],
        // After "Unselect all", the draft starts from nothing instead of the current stars.
        draftStartsEmpty: [
            false,
            {
                unselectAllStarred: () => true,
                setCustomizeSidebarOpen: (state, { open }) => (open ? false : state),
            },
        ],
        customizeSearch: [
            '',
            {
                setCustomizeSearch: (_, { search }) => search,
                setCustomizeSidebarOpen: (state, { open }) => (open ? '' : state),
            },
        ],
        starredProductsSaving: [
            false,
            {
                saveStarredProducts: () => true,
                saveStarredProductsSuccess: () => false,
                saveStarredProductsFailure: () => false,
            },
        ],
        // pinned: persisted under this logic's path, so renaming the reducer resets everyone's choice.
        // Storybook starts open so visual snapshots cover the full list.
        allProductsOpen: [
            inStorybook() || inStorybookTestRunner(),
            { persist: true },
            { setAllProductsOpen: (_, { open }) => open },
        ],
        // The browser's find-in-page opened the list to show a match. Not persisted, so the list
        // closes again on the next navigation instead of staying open for good.
        allProductsRevealedByFind: [
            false,
            {
                revealAllProductsForFind: () => true,
                setAllProductsOpen: () => false,
                locationChanged: () => false,
            },
        ],
    }),
    selectors({
        appRecommendationsEnabled: [
            (s) => [s.featureFlags, s.preflight, s.dataProcessingAccepted],
            (
                featureFlags: FeatureFlagsSet,
                preflight: PreflightStatus | null,
                dataProcessingAccepted: boolean
            ): boolean =>
                dataProcessingAccepted && !!(preflight?.is_debug || featureFlags[FEATURE_FLAGS.ML_INFERENCE_DECISIONS]),
        ],
        rankedConfigurableApps: [
            (s) => [s.configurableProducts, s.appRankings, s.appRecommendationQuery, s.appRecommendationsEnabled],
            (
                items: FileSystemImport[],
                rankings: Record<string, number> | null,
                query: string,
                enabled: boolean
            ): FileSystemImport[] =>
                enabled && query.trim() && rankings
                    ? [...items].sort((a, b) => (rankings[b.path] ?? 0) - (rankings[a.path] ?? 0))
                    : items,
        ],
        appMatchGroups: [
            (s) => [s.rankedConfigurableApps, s.appRankings, s.appRecommendationQuery, s.appRecommendationsEnabled],
            (
                items: FileSystemImport[],
                rankings: Record<string, number> | null,
                query: string,
                enabled: boolean
            ): AppMatchGroups | null =>
                enabled && query.trim() && rankings
                    ? {
                          matching: items.filter((item) => (rankings[item.path] ?? 0) >= APP_MATCH_THRESHOLD),
                          other: items.filter((item) => (rankings[item.path] ?? 0) < APP_MATCH_THRESHOLD),
                      }
                    : null,
        ],
        allItems: [
            (s) => [s.featureFlags, s.currentTeam],
            (featureFlags: FeatureFlagsSet, currentTeam: TeamPublicType | TeamType | null): FileSystemImport[] =>
                getNavProductItems(featureFlags, currentTeam?.created_at),
        ],
        pinnedItems: [
            (s) => [s.allItems, s.search],
            (items: FileSystemImport[], search: string): FileSystemImport[] => pinnedNavProducts(items, search),
        ],
        groupedItems: [
            (s) => [s.allItems, s.search],
            (items: FileSystemImport[], search: string): ProductsItemGroup[] => groupNavProducts(items, search),
        ],
        configurableProducts: [
            (s) => [s.allItems],
            (items: FileSystemImport[]): FileSystemImport[] =>
                items
                    .filter((item) => item.category !== PINNED_CATEGORY && !getProductAccessDisabledReason(item))
                    .sort((a, b) => productsItemName(a).localeCompare(productsItemName(b))),
        ],
        starredProductIds: [
            (s) => [s.allItems, s.shortcutData],
            (items: FileSystemImport[], shortcuts: FileSystemEntry[]): Record<string, string> => {
                const ids: Record<string, string> = {}
                for (const item of items) {
                    const shortcut = findProductShortcut(item, shortcuts)
                    if (shortcut) {
                        ids[item.path] = shortcut.id
                    }
                }
                return ids
            },
        ],
        customizeProductGroups: [
            (s) => [s.configurableProducts, s.customizeSearch, s.appMatchGroups],
            (items: FileSystemImport[], search: string, appMatchGroups: AppMatchGroups | null): ProductsItemGroup[] => {
                if (!appMatchGroups) {
                    return groupProducts(items, search)
                }
                const suggested = appMatchGroups.matching.filter((item) => productMatchesSearch(item, search))
                const rest = groupProducts(appMatchGroups.other, search)
                return suggested.length > 0 ? [{ label: SUGGESTED_GROUP_LABEL, items: suggested }, ...rest] : rest
            },
        ],
        initialStarredPaths: [
            (s) => [s.configurableProducts, s.starredProductIds],
            (items: FileSystemImport[], starredProductIds: Record<string, string>): string[] =>
                items.filter((item) => !!starredProductIds[item.path]).map((item) => item.path),
        ],
        draftStarredPaths: [
            (s) => [s.configurableProducts, s.initialStarredPaths, s.draftStarredChanges, s.draftStartsEmpty],
            (
                items: FileSystemImport[],
                initialStarredPaths: string[],
                draftStarredChanges: Record<string, boolean>,
                draftStartsEmpty: boolean
            ): Set<string> => {
                const initial = new Set(draftStartsEmpty ? [] : initialStarredPaths)
                return new Set(
                    items
                        .filter((item) => draftStarredChanges[item.path] ?? initial.has(item.path))
                        .map((item) => item.path)
                )
            },
        ],
        hasDraftStarredChanges: [
            (s) => [s.draftStarredPaths, s.initialStarredPaths],
            (draftStarredPaths: Set<string>, initialStarredPaths: string[]): boolean =>
                draftStarredPaths.size !== initialStarredPaths.length ||
                initialStarredPaths.some((path) => !draftStarredPaths.has(path)),
        ],
        // Only a sidebar with starred products has something to show above the list, so only then can it close.
        allProductsCollapsible: [
            (s) => [s.shortcutDataHasLoaded, s.starredProductIds],
            (shortcutDataHasLoaded: boolean, starredProductIds: Record<string, string>): boolean =>
                shortcutDataHasLoaded && Object.keys(starredProductIds).length > 0,
        ],
        // A search always shows its matches, even when the list is closed.
        allProductsVisible: [
            (s) => [
                s.allProductsOpen,
                s.allProductsRevealedByFind,
                s.allProductsCollapsible,
                s.search,
                s.shortcutDataHasLoaded,
            ],
            (
                allProductsOpen: boolean,
                allProductsRevealedByFind: boolean,
                allProductsCollapsible: boolean,
                search: string,
                shortcutDataHasLoaded: boolean
            ): boolean =>
                allProductsOpen ||
                allProductsRevealedByFind ||
                !!search.trim() ||
                (shortcutDataHasLoaded && !allProductsCollapsible),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        // A sidebar shown open because nothing was starred stays open after the first star.
        const keepAllProductsOpenWithoutStars = (): void => {
            if (values.shortcutDataHasLoaded && !values.allProductsCollapsible && !values.allProductsOpen) {
                actions.setAllProductsOpen(true)
            }
        }
        return {
            loadCurrentTeamSuccess: () => {
                if (cache.appConfigurationTeamId !== values.currentTeamId) {
                    cache.appConfigurationTeamId = values.currentTeamId
                    actions.resetAppConfiguration()
                }
            },
            resetAppConfiguration: () => {
                actions.setAppRecommendationQuery('')
            },
            setAppRecommendationQuery: ({ query }) => actions.rankApps({ query }),
            loadShortcutsSuccess: keepAllProductsOpenWithoutStars,
            loadShortcutsFailure: keepAllProductsOpenWithoutStars,
            deleteShortcutSuccess: keepAllProductsOpenWithoutStars,
            revealAllProductsForFind: () => {
                posthog.capture('sidebar all products revealed by find')
            },
            setDraftStarred: ({ starred }) => {
                // Picking a star means the starred list, not the full catalog, leads the sidebar.
                if (starred && values.allProductsOpen) {
                    actions.setAllProductsOpen(false)
                }
            },
            saveStarredProducts: async () => {
                // The footer buttons are disabled in these states, but the intro link and repeated
                // dispatches reach this listener directly.
                if (cache.starredSaveInFlight) {
                    return
                }
                const teamId = values.currentTeamId
                if (teamId === null || !values.shortcutDataHasLoaded) {
                    actions.saveStarredProductsFailure()
                    return
                }
                const { draftStarredPaths, starredProductIds, draftStartsEmpty } = values
                // New stars follow the order the dialog lists them in.
                const orderedProducts = groupProducts(values.configurableProducts, '').flatMap((group) => group.items)
                const configurablePaths = new Set(orderedProducts.map((item) => item.path))
                const add = orderedProducts
                    .filter((item) => draftStarredPaths.has(item.path) && !starredProductIds[item.path])
                    .map(shortcutFromEntry)
                const removeIds = [
                    ...orderedProducts
                        .filter((item) => !draftStarredPaths.has(item.path) && starredProductIds[item.path])
                        .map((item) => starredProductIds[item.path]),
                    // "Unselect all" and the clean slate also clear stars the dialog cannot list,
                    // such as a product the user has since lost access to.
                    ...(draftStartsEmpty
                        ? Object.entries(starredProductIds)
                              .filter(([path]) => !configurablePaths.has(path))
                              .map(([, id]) => id)
                        : []),
                ]

                if (add.length > 0 || removeIds.length > 0) {
                    cache.starredSaveInFlight = true
                    try {
                        const shortcuts = await fileSystemShortcutBulkUpdateCreate(String(teamId), {
                            add,
                            remove_ids: removeIds,
                        })
                        // A response for a project the user already left would overwrite the new project's stars.
                        if (values.currentTeamId !== teamId) {
                            actions.saveStarredProductsFailure()
                            return
                        }
                        actions.loadShortcutsSuccess((shortcuts as FileSystemEntry[]).map(withProductShortcutHref))
                    } catch (error) {
                        console.error('Failed to save starred products:', error)
                        lemonToast.error('Could not save your starred products. Try again.')
                        actions.saveStarredProductsFailure()
                        return
                    } finally {
                        cache.starredSaveInFlight = false
                    }
                }
                posthog.capture('sidebar starred products saved', {
                    // pinned: saved insights filter on this value
                    mode: 'customize',
                    added_count: add.length,
                    removed_count: removeIds.length,
                    starred_count: draftStarredPaths.size,
                })
                actions.saveStarredProductsSuccess()
            },
            setSearch: ({ search }) => {
                projectTreeLogic({
                    key: PRODUCTS_STARRED_TREE_KEY,
                    root: 'shortcuts://',
                    shortcutScope: 'products',
                }).actions.setSearchTerm(search)
            },
        }
    }),
    afterMount(({ cache, values }) => {
        cache.appConfigurationTeamId = values.currentTeamId
    }),
])
