export const navProductsTabLogic = kea<navProductsTabLogicType>([
    path(['layout', 'panel-layout', 'navbar', 'tabs', 'navProductsTabLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId'],
            preflightLogic,
            ['preflight'],
            featureFlagLogic,
            ['featureFlags'],
            aiConsentLogic,
            ['dataProcessingAccepted'],
            projectTreeDataLogic,
            ['groupItems', 'shortcutData', 'shortcutDataLoading'],
        ],
        actions: [projectTreeDataLogic, ['loadShortcutsSuccess']],
        logic: [projectTreeLogic({ key: PRODUCTS_STARRED_TREE_KEY, root: 'shortcuts://', shortcutScope: 'products' })],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setAppRecommendationQuery: (query: string) => ({ query }),
        queueAppStar: (productPath: string, starred: boolean) => ({ productPath, starred }),
        finishAppStar: (productPath: string, starred: boolean) => ({ productPath, starred }),
        setStarSaveError: (error: string | null) => ({ error }),
        setAppRankingError: (error: string | null) => ({ error }),
        setConfigureStarredOpen: (open: boolean) => ({ open }),
        setProductStarred: (productPath: string, starred: boolean) => ({ productPath, starred }),
    }),
    loaders(({ actions, values, cache }) => ({
        starSaveResult: [
            null as null,
            {
                saveAppStars: async () => {
                    while (Object.keys(values.pendingAppStars).length > 0) {
                        const [productPath, starred] = Object.entries(values.pendingAppStars)[0]
                        const item = values.configurableProducts.find((app) => app.path === productPath)
                        const shortcutId = values.starredProductIds[productPath]
                        try {
                            if (item && values.currentTeamId !== null) {
                                const shortcutPath = joinPath(splitPath(item.path).slice(-1))
                                if (starred && !shortcutId) {
                                    const entry = await coreApi.fileSystemShortcutCreate(String(values.currentTeamId), {
                                        path: shortcutPath,
                                        type: item.iconType || item.type,
                                        href: item.href,
                                    })
                                    actions.loadShortcutsSuccess([
                                        ...values.shortcutData,
                                        {
                                            id: entry.id,
                                            path: entry.path,
                                            type: entry.type,
                                            href: entry.href ?? undefined,
                                        },
                                    ])
                                    eventUsageLogic.actions.reportNavbarStarredItemAdded(
                                        item.iconType || item.type || 'unknown',
                                        shortcutPath
                                    )
                                } else if (!starred && shortcutId) {
                                    await coreApi.fileSystemShortcutDestroy(String(values.currentTeamId), shortcutId)
                                    actions.loadShortcutsSuccess(
                                        values.shortcutData.filter((entry) => entry.id !== shortcutId)
                                    )
                                    eventUsageLogic.actions.reportNavbarStarredItemRemoved(
                                        item.iconType || item.type || 'unknown',
                                        shortcutPath
                                    )
                                }
                            }
                        } catch {
                            actions.setStarSaveError(
                                'Some changes could not be saved. Toggle those apps again to retry.'
                            )
                        }
                        actions.finishAppStar(productPath, starred)
                    }
                    return null
                },
            },
        ],
        appRankings: [
            null as Record<string, number> | null,
            {
                rankApps: async ({ query }: { query: string }, breakpoint) => {
                    cache.disposables.dispose('appRankingRequest')
                    actions.setAppRankingError(null)
                    if (!query.trim() || !values.appRecommendationsEnabled || values.currentTeamId === null) {
                        return null
                    }
                    await breakpoint(500)
                    if (!values.appRecommendationsEnabled) {
                        return null
                    }
                    const controller = new AbortController()
                    cache.disposables.add(() => () => controller.abort(), 'appRankingRequest', {
                        pauseOnPageHidden: false,
                    })
                    const items = values.configurableProducts
                    try {
                        const scores = await Promise.all(
                            buildAppRankingQuestions(items).map(async (questions) => {
                                const result = await withTimeout(
                                    decisionsApi.mlInferenceDecisionsDecideCreate(
                                        String(values.currentTeamId),
                                        {
                                            state: query.trim(),
                                            questions,
                                        },
                                        { signal: controller.signal }
                                    ),
                                    10000
                                )
                                return readAppRankings(result, items)
                            })
                        )
                        breakpoint()
                        return values.appRecommendationsEnabled ? Object.assign({}, ...scores) : null
                    } catch {
                        breakpoint()
                        actions.setAppRankingError(
                            'Jev could not suggest apps. Edit your description to try again, or choose from all apps below.'
                        )
                        return null
                    } finally {
                        controller.abort()
                    }
                },
            },
        ],
    })),
    reducers({
        appRecommendationQuery: ['', { setAppRecommendationQuery: (_, { query }) => query }],
        appRankingError: [null as string | null, { setAppRankingError: (_, { error }) => error }],
        starSaveError: [
            null as string | null,
            {
                setStarSaveError: (_, { error }) => error,
                queueAppStar: () => null,
            },
        ],
        pendingAppStars: [
            {} as Record<string, boolean>,
            {
                queueAppStar: (state, { productPath, starred }) => ({ ...state, [productPath]: starred }),
                finishAppStar: (state, { productPath, starred }) => {
                    if (state[productPath] !== starred) {
                        return state
                    }
                    const remaining = { ...state }
                    delete remaining[productPath]
                    return remaining
                },
            },
        ],
        search: ['', { setSearch: (_, { search }) => search }],
        configureStarredOpen: [false, { setConfigureStarredOpen: (_, { open }) => open }],
    }),
    selectors({
        appRecommendationsEnabled: [
            (s) => [s.featureFlags, s.preflight, s.dataProcessingAccepted],
            (
                featureFlags: FeatureFlagsSet,
                preflight: PreflightStatus | null,
                dataProcessingAccepted: boolean
            ): boolean =>
                dataProcessingAccepted && !!(preflight?.is_debug || featureFlags[FEATURE_FLAGS.ML_INFERENCE_DECISIONS]),
        ],
        rankedConfigurableApps: [
            (s) => [s.configurableProducts, s.appRankings, s.appRecommendationQuery, s.appRecommendationsEnabled],
            (
                items: FileSystemImport[],
                rankings: Record<string, number> | null,
                query: string,
                enabled: boolean
            ): FileSystemImport[] =>
                enabled && query.trim() && rankings
                    ? [...items].sort((a, b) => (rankings[b.path] ?? 0) - (rankings[a.path] ?? 0))
                    : items,
        ],
        appMatchGroups: [
            (s) => [s.rankedConfigurableApps, s.appRankings, s.appRecommendationQuery, s.appRecommendationsEnabled],
            (
                items: FileSystemImport[],
                rankings: Record<string, number> | null,
                query: string,
                enabled: boolean
            ): AppMatchGroups | null =>
                enabled && query.trim() && rankings
                    ? {
                          matching: items.filter((item) => (rankings[item.path] ?? 0) >= APP_MATCH_THRESHOLD),
                          other: items.filter((item) => (rankings[item.path] ?? 0) < APP_MATCH_THRESHOLD),
                      }
                    : null,
        ],
        selectedAppStars: [
            (s) => [s.starredProductIds, s.pendingAppStars],
            (ids: Record<string, string>, pending: Record<string, boolean>): Record<string, boolean> => ({
                ...Object.fromEntries(Object.keys(ids).map((path) => [path, true])),
                ...pending,
            }),
        ],
        allItems: [
            (s) => [s.featureFlags, s.groupItems],
            (featureFlags: FeatureFlagsSet, groupItems: FileSystemImport[]): FileSystemImport[] => {
                const items: FileSystemImport[] = [
                    { path: 'Home', category: 'Project', iconType: 'home', href: urls.projectRoot(), visualOrder: 0 },
                    {
                        path: 'Activity',
                        category: 'Project',
                        iconType: 'activity',
                        href: urls.activity(ActivityTab.ExploreEvents),
                        visualOrder: 2,
                    },
                    ...getDefaultTreeProducts().map(
                        (item): FileSystemImport =>
                            item.href === urls.inbox()
                                ? {
                                      ...item,
                                      displayLabel: 'Self-driving',
                                      category: 'Project',
                                      visualOrder: 1,
                                      tags: ['beta'],
                                  }
                                : item
                    ),
                    ...getDefaultTreeDataAndPeople(),
                    ...groupItems,
                ]
                const destinations = new Map<string, FileSystemImport>()
                for (const item of items) {
                    if (!item.href || (item.flag && !featureFlags[item.flag as keyof FeatureFlagsSet])) {
                        continue
                    }
                    const existing = destinations.get(item.href)
                    destinations.set(item.href, existing ? { ...item, ...existing } : item)
                }
                return [...destinations.values()]
            },
        ],
        groupedItems: [
            (s) => [s.allItems, s.search],
            (items: FileSystemImport[], search: string): ProductsItemGroup[] => groupProducts(items, search),
        ],
        configurableProducts: [
            (s) => [s.allItems],
            (items: FileSystemImport[]): FileSystemImport[] =>
                items
                    .filter((item) => !getProductAccessDisabledReason(item))
                    .sort((a, b) => productsItemName(a).localeCompare(productsItemName(b))),
        ],
        starredProductIds: [
            (s) => [s.allItems, s.shortcutData],
            (items: FileSystemImport[], shortcuts: FileSystemEntry[]): Record<string, string> => {
                const ids: Record<string, string> = {}
                for (const item of items) {
                    const shortcutPath = joinPath(splitPath(item.path).slice(-1))
                    const shortcut = shortcuts.find(
                        (entry) => entry.type !== 'folder' && !entry.ref && entry.path === shortcutPath
                    )
                    if (shortcut) {
                        ids[item.path] = shortcut.id
                    }
                }
                return ids
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setAppRecommendationQuery: ({ query }) => actions.rankApps({ query }),
        setProductStarred: ({ productPath, starred }) => {
            if (!values.configurableProducts.some((app) => app.path === productPath)) {
                return
            }
            actions.queueAppStar(productPath, starred)
        },
        queueAppStar: async (_, breakpoint) => {
            await breakpoint(250)
            if (!values.starSaveResultLoading) {
                actions.saveAppStars()
            }
        },
        setSearch: ({ search }) => {
            projectTreeLogic({
                key: PRODUCTS_STARRED_TREE_KEY,
                root: 'shortcuts://',
                shortcutScope: 'products',
            }).actions.setSearchTerm(search)
        },
    })),
])
