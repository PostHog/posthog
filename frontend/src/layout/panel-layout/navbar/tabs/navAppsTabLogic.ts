import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { urls } from 'scenes/urls'

import { FileSystemImport } from '~/queries/schema/schema-general'
import { ActivityTab } from '~/types'

import { getDefaultTreeDataAndPeople, getDefaultTreeProducts } from '../../ProjectTree/defaultTree'
import { projectTreeDataLogic } from '../../ProjectTree/projectTreeDataLogic'
import { projectTreeLogic } from '../../ProjectTree/projectTreeLogic'
import { AppsItemGroup, groupApps } from './appsCatalog'

export const APPS_STARRED_TREE_KEY = 'navbar-apps-starred'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface navAppsTabLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    groupItems: FileSystemImport[] // projectTreeDataLogic
    allItems: FileSystemImport[]
    groupedItems: AppsItemGroup[]
    search: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface navAppsTabLogicActions {
    setSearch: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface navAppsTabLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        allItems: (featureFlags: FeatureFlagsSet, groupItems: FileSystemImport[]) => FileSystemImport[]
        groupedItems: (allItems: FileSystemImport[], search: string) => AppsItemGroup[]
    }
}

export type navAppsTabLogicType = MakeLogicType<
    navAppsTabLogicValues,
    navAppsTabLogicActions,
    Record<string, any>,
    navAppsTabLogicMeta
>

export const navAppsTabLogic = kea<navAppsTabLogicType>([
    path(['layout', 'panel-layout', 'navbar', 'tabs', 'navAppsTabLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], projectTreeDataLogic, ['groupItems']],
        logic: [projectTreeLogic({ key: APPS_STARRED_TREE_KEY, root: 'shortcuts://', shortcutScope: 'apps' })],
    })),
    actions({ setSearch: (search: string) => ({ search }) }),
    reducers({ search: ['', { setSearch: (_, { search }) => search }] }),
    selectors({
        allItems: [
            (s) => [s.featureFlags, s.groupItems],
            (featureFlags: FeatureFlagsSet, groupItems: FileSystemImport[]): FileSystemImport[] => {
                const items: FileSystemImport[] = [
                    { path: 'Home', category: 'Project', iconType: 'home', href: urls.projectRoot(), visualOrder: 0 },
                    {
                        path: 'Activity',
                        category: 'Project',
                        iconType: 'activity',
                        href: urls.activity(ActivityTab.ExploreEvents),
                        visualOrder: 2,
                    },
                    ...getDefaultTreeProducts().map(
                        (item): FileSystemImport =>
                            item.href === urls.inbox()
                                ? {
                                      ...item,
                                      displayLabel: 'Self-driving',
                                      category: 'Project',
                                      visualOrder: 1,
                                      tags: ['beta'],
                                  }
                                : item
                    ),
                    ...getDefaultTreeDataAndPeople(),
                    ...groupItems,
                ]
                const destinations = new Map<string, FileSystemImport>()
                for (const item of items) {
                    if (!item.href || (item.flag && !featureFlags[item.flag as keyof FeatureFlagsSet])) {
                        continue
                    }
                    const existing = destinations.get(item.href)
                    destinations.set(item.href, existing ? { ...item, ...existing } : item)
                }
                return [...destinations.values()]
            },
        ],
        groupedItems: [
            (s) => [s.allItems, s.search],
            (items: FileSystemImport[], search: string): AppsItemGroup[] => groupApps(items, search),
        ],
    }),
    listeners({
        setSearch: ({ search }) => {
            projectTreeLogic({
                key: APPS_STARRED_TREE_KEY,
                root: 'shortcuts://',
                shortcutScope: 'apps',
            }).actions.setSearchTerm(search)
        },
    }),
])
