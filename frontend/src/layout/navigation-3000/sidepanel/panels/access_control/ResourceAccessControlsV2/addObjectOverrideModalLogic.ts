export const addObjectOverrideModalLogic = kea<addObjectOverrideModalLogicType>([
    path((key) => ['scenes', 'access_control', 'addObjectOverrideModalLogic', key]),
    props({} as AddObjectOverrideModalLogicProps),
    key((props) => `${props.projectId}:${props.scopeType}:${props.subjectId}`),

    connect((props: AddObjectOverrideModalLogicProps) => ({
        actions: [accessDetailLogic(props), ['setObjectRule']],
    })),

    actions({
        openModal: true,
        closeModal: true,
        setResource: (resource: APIScopeObject) => ({ resource }),
        setSearch: (search: string) => ({ search }),
        setObjectId: (objectId: string | null) => ({ objectId }),
        setSelectedObject: (option: ObjectOption | null) => ({ option }),
        setLevel: (level: AccessControlLevel) => ({ level }),
        submitRule: true,
    }),

    reducers({
        isOpen: [false, { openModal: () => true, closeModal: () => false }],
        resource: [
            'dashboard' as APIScopeObject,
            { setResource: (_, { resource }) => resource, closeModal: () => 'dashboard' as APIScopeObject },
        ],
        search: ['', { setSearch: (_, { search }) => search, setResource: () => '', closeModal: () => '' }],
        objectId: [
            null as string | null,
            { setObjectId: (_, { objectId }) => objectId, setResource: () => null, closeModal: () => null },
        ],
        /** The picked option, kept so its label survives the option list reloading. */
        selectedObject: [
            null as ObjectOption | null,
            { setSelectedObject: (_, { option }) => option, setResource: () => null, closeModal: () => null },
        ],
        level: [
            AccessControlLevel.None as AccessControlLevel,
            { setLevel: (_, { level }) => level, closeModal: () => AccessControlLevel.None },
        ],
    }),

    loaders(({ props, values }) => ({
        objectOptions: [
            [] as ObjectOption[],
            {
                loadObjectOptions: async (_, breakpoint) => {
                    await breakpoint(300)
                    const response = await api.get<{ results: Record<string, any>[] }>(
                        `api/projects/${props.projectId}/${resourceToApiRoute(values.resource)}/?limit=20&search=${encodeURIComponent(
                            values.search
                        )}`
                    )
                    return response.results.map((item) => ({
                        id: String(item.id),
                        name: item.name || item.title || item.derived_name || item.key || String(item.id),
                    }))
                },
            },
        ],
    })),

    selectors({
        // Selecting an option resets the search, which reloads the options; keep the picked one in
        // the list so LemonInputSelect can render its name instead of the raw id
        displayObjectOptions: [
            (s) => [s.objectOptions, s.selectedObject],
            (objectOptions: ObjectOption[], selectedObject: ObjectOption | null): ObjectOption[] =>
                selectedObject && !objectOptions.some((o) => o.id === selectedObject.id)
                    ? [selectedObject, ...objectOptions]
                    : objectOptions,
        ],
    }),

    listeners(({ actions, values }) => ({
        openModal: () => actions.loadObjectOptions(null),
        setResource: () => actions.loadObjectOptions(null),
        setSearch: () => actions.loadObjectOptions(null),
        setObjectId: ({ objectId }) => {
            actions.setSelectedObject(objectId ? (values.objectOptions.find((o) => o.id === objectId) ?? null) : null)
        },
        submitRule: () => {
            // isOpen guards a double click: the first submit closes the modal synchronously
            if (!values.isOpen || !values.objectId) {
                return
            }
            actions.setObjectRule(values.resource, values.objectId, values.level)
            actions.closeModal()
        },
    })),
])
