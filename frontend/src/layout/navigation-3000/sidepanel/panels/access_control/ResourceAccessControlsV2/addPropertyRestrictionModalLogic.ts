export const addPropertyRestrictionModalLogic = kea<addPropertyRestrictionModalLogicType>([
    path((key) => ['scenes', 'access_control', 'addPropertyRestrictionModalLogic', key]),
    props({} as AddPropertyRestrictionModalLogicProps),
    key((props) => `${props.projectId}:${props.scopeType}:${props.subjectId}`),

    connect((props: AddPropertyRestrictionModalLogicProps) => ({
        actions: [accessDetailLogic(props), ['setPropertyRule', 'propertyRuleSaved']],
        values: [accessDetailLogic(props), ['properties', 'ruleSaving']],
    })),

    actions({
        openModal: true,
        closeModal: true,
        setPropertyType: (propertyType: 'person' | 'event' | 'ai') => ({ propertyType }),
        setSearch: (search: string) => ({ search }),
        setPropertyId: (propertyId: string | null) => ({ propertyId }),
        setSelectedProperty: (option: PropertyOption | null) => ({ option }),
        setLevel: (level: AccessLevelEnumApi) => ({ level }),
        submitRule: true,
    }),

    reducers({
        isOpen: [false, { openModal: () => true, closeModal: () => false }],
        propertyType: [
            'person' as 'person' | 'event' | 'ai',
            { setPropertyType: (_, { propertyType }) => propertyType, closeModal: () => 'person' },
        ],
        search: ['', { setSearch: (_, { search }) => search, setPropertyType: () => '', closeModal: () => '' }],
        propertyId: [
            null as string | null,
            { setPropertyId: (_, { propertyId }) => propertyId, setPropertyType: () => null, closeModal: () => null },
        ],
        /** The picked option, kept so its label survives the option list reloading. */
        selectedProperty: [
            null as PropertyOption | null,
            { setSelectedProperty: (_, { option }) => option, setPropertyType: () => null, closeModal: () => null },
        ],
        level: [
            AccessLevelEnumApi.Read as AccessLevelEnumApi,
            { setLevel: (_, { level }) => level, closeModal: () => AccessLevelEnumApi.Read },
        ],
    }),

    loaders(({ props, values }) => ({
        propertyOptions: [
            [] as PropertyOption[],
            {
                loadPropertyOptions: async (_, breakpoint) => {
                    await breakpoint(300)
                    if (values.propertyType === 'ai') {
                        const words = values.search.trim().toLowerCase().split(/\s+/)
                        return Object.values(AIEventPropertyEnumApi)
                            .map((name) => ({
                                id: name,
                                name: `${name.slice(4)} (${name})`,
                            }))
                            .filter((option) => words.every((word) => option.name.toLowerCase().includes(word)))
                            .sort((a, b) => a.name.localeCompare(b.name))
                    }
                    const response = await propertyDefinitionsList(props.projectId, {
                        type: values.propertyType,
                        limit: 20,
                        search: values.search,
                    })
                    breakpoint()
                    return response.results.map((item) => ({ id: item.id, name: item.name }))
                },
            },
        ],
    })),

    selectors({
        /** The rule already stored for the picked property, so the modal offers an update, not a silent overwrite. */
        existingRule: [
            (s) => [s.properties, s.propertyId, s.propertyType],
            (
                properties: AccessPropertyRule[],
                propertyId: string | null,
                propertyType: 'ai' | 'event' | 'person'
            ): AccessPropertyRule | null =>
                propertyId
                    ? (properties.find((p) =>
                          propertyType === 'ai'
                              ? p.property_type === 'event' && p.property === propertyId
                              : p.property_definition_id === propertyId
                      ) ?? null)
                    : null,
        ],

        // Selecting an option resets the search, which reloads the options; keep the picked one in
        // the list so LemonInputSelect can render its name instead of the raw id
        displayPropertyOptions: [
            (s) => [s.propertyOptions, s.selectedProperty, s.propertyOptionsLoading],
            (
                propertyOptions: PropertyOption[],
                selectedProperty: PropertyOption | null,
                loading: boolean
            ): PropertyOption[] => {
                const options = loading ? [] : propertyOptions
                return selectedProperty && !options.some((o) => o.id === selectedProperty.id)
                    ? [selectedProperty, ...options]
                    : options
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        openModal: () => actions.loadPropertyOptions(null),
        setPropertyType: () => actions.loadPropertyOptions(null),
        setSearch: () => actions.loadPropertyOptions(null),
        setPropertyId: ({ propertyId }) => {
            actions.setSelectedProperty(
                propertyId ? (values.propertyOptions.find((o) => o.id === propertyId) ?? null) : null
            )
        },
        propertyRuleSaved: () => actions.closeModal(),
        submitRule: () => {
            if (!values.isOpen || !values.propertyId || values.ruleSaving || values.propertyOptionsLoading) {
                return
            }
            const aiProperty =
                values.propertyType === 'ai'
                    ? Object.values(AIEventPropertyEnumApi).find((name) => name === values.propertyId)
                    : undefined
            actions.setPropertyRule(
                values.existingRule?.property_definition_id ?? values.propertyId,
                values.level,
                aiProperty
            )
        },
    })),
])
