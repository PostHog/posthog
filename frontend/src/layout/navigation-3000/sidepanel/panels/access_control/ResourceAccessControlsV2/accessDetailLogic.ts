import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import api from 'lib/api'

import { AccessControlLevel } from '~/types'

import {
    propertyAccessControlsCreate,
    propertyAccessControlsDestroy,
} from 'products/access_control/frontend/generated/api'
import { AccessLevelEnumApi } from 'products/access_control/frontend/generated/api.schemas'

/** Who a set of rules belongs to. 'default' is the project itself: rules that apply to everyone. */
export type AccessScope = 'member' | 'role' | 'default'

/** Where the level that takes over on removing a rule comes from. */
export type AccessInheritedSource = 'role' | 'resource' | 'object_default' | 'built_in' | 'organization_admin'

export interface AccessObjectRule {
    resource: string
    resource_id: string
    name: string
    access_level: AccessControlLevel
    /** What applies to this object once the rule is removed. */
    inherited_access_level: AccessControlLevel | null
    inherited_access_level_source: AccessInheritedSource
}

export interface AccessPropertyRule {
    property_definition_id: string
    property: string
    property_type: 'person' | 'event'
    access_level: AccessLevelEnumApi
}

export interface AccessDetailLogicProps {
    projectId: string
    scopeType: AccessScope
    subjectId: string
}

export interface AccessDetailSubject {
    scopeType: AccessScope
    subjectId: string
}

/** Parses the side panel's `member:<id>` / `role:<id>` options, used for deep links into the panel. */
export function parseAccessDetailOptions(options: string | null): AccessDetailSubject | null {
    const [scope, subjectId] = (options ?? '').split(':')
    if (!subjectId) {
        return null
    }
    return { scopeType: scope === 'role' ? 'role' : 'member', subjectId }
}

// Object resource types whose list `id` maps directly to their `/{route}/{id}/access_controls` endpoint.
export const OBJECT_RULE_RESOURCES: { value: string; label: string; route: string }[] = [
    { value: 'dashboard', label: 'Dashboard', route: 'dashboards' },
    { value: 'insight', label: 'Insight', route: 'insights' },
    { value: 'feature_flag', label: 'Feature flag', route: 'feature_flags' },
    { value: 'experiment', label: 'Experiment', route: 'experiments' },
    { value: 'survey', label: 'Survey', route: 'surveys' },
    { value: 'warehouse_table', label: 'Warehouse table', route: 'warehouse_tables' },
    { value: 'warehouse_view', label: 'Warehouse view', route: 'warehouse_saved_queries' },
]

export function objectRouteFor(resource: string): string {
    return OBJECT_RULE_RESOURCES.find((r) => r.value === resource)?.route ?? `${resource}s`
}

function endpoint(props: AccessDetailLogicProps, kind: 'objects' | 'properties'): string {
    const base = `api/projects/${props.projectId}`
    if (props.scopeType === 'default') {
        return `${base}/access_control_default_${kind}`
    }
    if (props.scopeType === 'role') {
        return `${base}/access_control_role_${kind}?role_id=${props.subjectId}`
    }
    return `${base}/access_control_member_${kind}?member_id=${props.subjectId}`
}

// The access-control write APIs target an org member or a role. Sending neither writes the
// project-wide rule, which is what the defaults scope wants.
function subjectBody(props: AccessDetailLogicProps): Record<string, string> {
    if (props.scopeType === 'default') {
        return {}
    }
    return props.scopeType === 'role' ? { role: props.subjectId } : { organization_member: props.subjectId }
}

