import { MakeLogicType, afterMount, kea, key, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'


export type AccessScope = 'member' | 'role'

export interface AccessObjectOverride {
    resource: string
    resource_id: string
    name: string
    access_level: string
    source: 'member' | 'role' | 'default'
    role_name: string | null
}

export interface AccessPropertyRestriction {
    property: string
    property_type: 'person' | 'event'
    access_level: string
    source: 'member' | 'role' | 'default'
    role_name: string | null
}

export interface AccessDetailLogicProps {
    projectId: string
    scopeType: AccessScope
    subjectId: string
}

export interface AccessDetailSubject {
    scopeType: AccessScope
    subjectId: string
}

/** Parses the side panel's `member:<id>` / `role:<id>` options, used for deep links into the panel. */
export function parseAccessDetailOptions(options: string | null): AccessDetailSubject | null {
    const [scope, subjectId] = (options ?? '').split(':')
    if (!subjectId) {
        return null
    }
    return { scopeType: scope === 'role' ? 'role' : 'member', subjectId }
}

function endpoint(props: AccessDetailLogicProps, kind: 'objects' | 'properties'): string {
    const base = `api/projects/${props.projectId}`
    if (props.scopeType === 'role') {
        return `${base}/access_control_role_${kind}?role_id=${props.subjectId}`
    }
    return `${base}/access_control_member_${kind}?member_id=${props.subjectId}`
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accessDetailLogicValues {
    objects: AccessObjectOverride[];
    objectsLoading: boolean;
    properties: AccessPropertyRestriction[];
    propertiesLoading: boolean;
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accessDetailLogicActions {
    loadObjects: () => any;
    loadObjectsFailure: (error: string, errorObject?: any) => {
        error: string;
        errorObject?: any;
    };
    loadObjectsSuccess: (objects: AccessObjectOverride[], payload?: any) => {
        objects: AccessObjectOverride[];
        payload?: any;
    };
    loadProperties: () => any;
    loadPropertiesFailure: (error: string, errorObject?: any) => {
        error: string;
        errorObject?: any;
    };
    loadPropertiesSuccess: (properties: AccessPropertyRestriction[], payload?: any) => {
        properties: AccessPropertyRestriction[];
        payload?: any;
    };
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface accessDetailLogicMeta {
    key: string;
}

export type accessDetailLogicType = MakeLogicType<accessDetailLogicValues, accessDetailLogicActions, AccessDetailLogicProps, accessDetailLogicMeta>;

export const accessDetailLogic = kea<accessDetailLogicType>([
    path((key) => ['scenes', 'access_control', 'accessDetailLogic', key]),
    props({} as AccessDetailLogicProps),
    key((props) => `${props.projectId}:${props.scopeType}:${props.subjectId}`),

    loaders(({ props }) => ({
        objects: [
            [] as AccessObjectOverride[],
            {
                loadObjects: async () =>
                    (await api.get<{ results: AccessObjectOverride[] }>(endpoint(props, 'objects'))).results,
            },
        ],
        properties: [
            [] as AccessPropertyRestriction[],
            {
                loadProperties: async () =>
                    (await api.get<{ results: AccessPropertyRestriction[] }>(endpoint(props, 'properties'))).results,
            },
        ],
    })),

    afterMount(({ actions }) => {
        actions.loadObjects()
        actions.loadProperties()
    }),
])
