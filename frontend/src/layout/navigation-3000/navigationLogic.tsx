import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'
import { subscriptions } from 'kea-subscriptions'
import posthog from 'posthog-js'

import { isEmbeddedPageFrame } from 'lib/utils/embeddedPageFrame'
import { organizationLogic } from 'scenes/organizationLogic'
import { projectLogic } from 'scenes/projectLogic'
import { sceneLogic } from 'scenes/sceneLogic'
import { Scene } from 'scenes/sceneTypes'

import type { SceneConfig } from '../../scenes/sceneTypes'
import type { ProjectType } from '../../types'
import { navigationLogic } from '../navigation/navigationLogic'

export type Navigation3000Mode = 'none' | 'minimal' | 'zen' | 'embedded' | 'full'

export type ZenModeTrigger = 'shortcut' | 'account_menu' | 'help_menu' | 'exit_button' | 'url'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface navigation3000LogicValues {
    mobileLayout: boolean // navigationLogic
    isCurrentOrganizationUnavailable: boolean // organizationLogic
    currentProject: ProjectType | null // projectLogic
    activeSceneId: string | null // sceneLogic
    sceneConfig: SceneConfig | null // sceneLogic
    mode: Navigation3000Mode
    zenMode: boolean
    zenModeFromUrl: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface navigation3000LogicActions {
    setZenMode: (
        zenMode: boolean,
        trigger: ZenModeTrigger
    ) => {
        trigger: ZenModeTrigger
        zenMode: boolean
    }
    toggleZenMode: (trigger: ZenModeTrigger) => {
        trigger: ZenModeTrigger
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface navigation3000LogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        zenModeFromUrl: (searchParams: Record<string, any>) => boolean
        mode: (
            sceneConfig: SceneConfig | null,
            isCurrentOrganizationUnavailable: boolean,
            currentProject: ProjectType | null,
            zenMode: boolean,
            activeSceneId: string | null
        ) => Navigation3000Mode
    }
}

export type navigation3000LogicType = MakeLogicType<
    navigation3000LogicValues,
    navigation3000LogicActions,
    Record<string, any>,
    navigation3000LogicMeta
>

export const navigation3000Logic = kea<navigation3000LogicType>([
    path(['layout', 'navigation-3000', 'navigationLogic']),
    connect(() => ({
        values: [
            sceneLogic,
            ['sceneConfig', 'activeSceneId'],
            navigationLogic,
            ['mobileLayout'],
            organizationLogic,
            ['isCurrentOrganizationUnavailable'],
            projectLogic,
            ['currentProject'],
        ],
    })),
    actions({
        setZenMode: (zenMode: boolean, trigger: ZenModeTrigger) => ({ zenMode, trigger }),
        toggleZenMode: (trigger: ZenModeTrigger) => ({ trigger }),
    }),
    reducers({
        zenMode: [
            false,
            { persist: true },
            {
                setZenMode: (_, { zenMode }) => zenMode,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setZenMode: ({ zenMode, trigger }) => {
            posthog.capture('zen mode toggled', { enabled: zenMode, trigger })
        },
        toggleZenMode: ({ trigger }) => {
            actions.setZenMode(!values.zenMode, trigger)
        },
    })),
    selectors({
        zenModeFromUrl: [
            () => [router.selectors.searchParams],
            (searchParams: Record<string, any>): boolean => {
                // Enable zen mode via ?zen or ?zen=true or ?zen=1
                const zenParam = searchParams?.zen
                return zenParam !== undefined && zenParam !== 'false' && zenParam !== '0'
            },
        ],
        mode: [
            (s) => [s.sceneConfig, s.isCurrentOrganizationUnavailable, s.currentProject, s.zenMode, s.activeSceneId],
            (
                sceneConfig: null | import('scenes/sceneTypes').SceneConfig,
                isCurrentOrganizationUnavailable: boolean,
                currentProject: import('~/types').ProjectType | null,
                zenMode: boolean,
                activeSceneId: string | null
            ): Navigation3000Mode => {
                // An embedded page frame sits inside another app page, so it shows the scene alone.
                if (isEmbeddedPageFrame()) {
                    return 'embedded'
                }
                if (zenMode) {
                    return 'zen'
                }
                // My tickets stays open on a project pending deletion, so hide the links into the rest of the app.
                if (isCurrentOrganizationUnavailable || currentProject?.is_pending_deletion) {
                    return 'minimal'
                }
                if (sceneConfig?.layout === 'plain' && !sceneConfig.allowUnauthenticated) {
                    // Onboarding owns the whole viewport, so it gets no navbar.
                    return activeSceneId === Scene.Onboarding ? 'none' : 'minimal'
                }
                return sceneConfig?.layout !== 'plain' ? 'full' : 'none'
            },
        ],
    }),
    subscriptions(({ actions, values }) => ({
        zenModeFromUrl: (zenModeFromUrl: boolean) => {
            // Enable zen mode when URL parameter is present (e.g., ?zen or ?zen=true)
            // Only enable, never disable from URL - user can manually disable
            if (zenModeFromUrl && !values.zenMode) {
                actions.setZenMode(true, 'url')
            }
        },
    })),
])
