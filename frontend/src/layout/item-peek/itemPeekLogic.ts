export type itemPeekLogicType = MakeLogicType<
    itemPeekLogicValues,
    itemPeekLogicActions,
    Record<string, any>,
    itemPeekLogicMeta
>

export const itemPeekLogic = kea<itemPeekLogicType>([
    path(['layout', 'item-peek', 'itemPeekLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], sceneLogic, ['exportedScenes']],
        actions: [router, ['locationChanged']],
    })),
    actions({
        openItemPeek: (target: ItemPeekTarget, fallbackName: string | null) => ({ target, fallbackName }),
        closeItemPeek: true,
        viewItemPeek: true,
        setLoadedScene: (loadedScene: ItemPeekLoadedScene | null) => ({ loadedScene }),
        setSceneFailed: (sceneId: string) => ({ sceneId }),
    }),
    reducers({
        target: [
            null as ItemPeekTarget | null,
            {
                openItemPeek: (_, { target }) => target,
                closeItemPeek: () => null,
            },
        ],
        fallbackName: [
            null as string | null,
            {
                openItemPeek: (_, { fallbackName }) => fallbackName,
                closeItemPeek: () => null,
            },
        ],
        loadedScene: [
            null as ItemPeekLoadedScene | null,
            {
                setLoadedScene: (_, { loadedScene }) => loadedScene,
                closeItemPeek: () => null,
            },
        ],
        failedSceneId: [
            null as string | null,
            {
                setSceneFailed: (_, { sceneId }) => sceneId,
                openItemPeek: () => null,
            },
        ],
    }),
    selectors({
        isOpen: [(s) => [s.target], (target): boolean => !!target],
        peekProps: [
            (s) => [s.target, s.loadedScene],
            (target, loadedScene): Record<string, any> | null => {
                if (!target || !loadedScene || loadedScene.sceneId !== target.sceneId) {
                    return null
                }
                const toProps = ITEM_PEEK_SCENES[target.sceneId]?.paramsToProps ?? loadedScene.scene.paramsToProps
                return { ...toProps?.(target.sceneParams) }
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openItemPeek: async ({ target }, breakpoint) => {
            posthog.capture('item peek opened', { scene_id: target.sceneId })
            if (values.loadedScene?.sceneId === target.sceneId) {
                return
            }
            const cached = values.exportedScenes[target.sceneId]
            if (cached && !ITEM_PEEK_SCENES[target.sceneId]?.load) {
                actions.setLoadedScene({ sceneId: target.sceneId, scene: cached })
                return
            }
            actions.setLoadedScene(null)
            let scene: SceneExport<any> | null = null
            try {
                scene = await importPeekScene(target.sceneId)
            } catch (error) {
                posthog.captureException(error, { extra: { source: 'itemPeekLogic', scene_id: target.sceneId } })
            }
            breakpoint()
            if (scene) {
                actions.setLoadedScene({ sceneId: target.sceneId, scene })
            } else {
                actions.setSceneFailed(target.sceneId)
            }
        },
        viewItemPeek: () => {
            posthog.capture('item peek viewed', { scene_id: values.target?.sceneId })
        },
        locationChanged: ({ pathname }) => {
            // A changed search or hash keeps the drawer, since some scenes write their own state there.
            if (cache.lastPathname !== undefined && cache.lastPathname !== pathname && values.target) {
                actions.closeItemPeek()
            }
            cache.lastPathname = pathname
        },
    })),
    afterMount(({ actions, values, cache }) => {
        cache.lastPathname = router.values.location.pathname
        cache.disposables.add(
            () =>
                registerLinkPeekHandler((href, element) => {
                    if (!values.featureFlags[FEATURE_FLAGS.ITEM_PEEK] || !element.closest(PEEK_SURFACES_SELECTOR)) {
                        return false
                    }
                    const target = resolveItemPeek(href)
                    // A link to the page already open, or to the item already peeked, opens that page in full.
                    const currentPath = resolveItemPeek(router.values.location.pathname)?.path
                    if (!target || target.path === currentPath || target.path === values.target?.path) {
                        return false
                    }
                    actions.openItemPeek(target, element.textContent?.trim() || null)
                    return true
                }),
            'linkPeekHandler'
        )
    }),
])
