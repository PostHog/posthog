import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'
import type { LocationChangedPayload } from 'kea-router/lib/types'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { registerLinkPeekHandler } from 'lib/lemon-ui/Link/linkPeekRegistry'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { retryImport } from 'lib/utils/retryImport'
import { appScenes } from 'scenes/appScenes'
import { sceneLogic } from 'scenes/sceneLogic'
import { SceneExport, SceneProps } from 'scenes/sceneTypes'

import { ITEM_PEEK_SCENES } from './itemPeekScenes'
import { ItemPeekTarget, resolveItemPeek } from './resolveItemPeek'

export interface ItemPeekLoadedScene {
    sceneId: string
    scene: SceneExport<any>
}

/** Links inside the scene, or inside the drawer itself, peek. The navigation and the menus keep navigating. */
// pinned: the drawer's `data-attr` doubles as this selector, so renaming it stops links inside the drawer from peeking.
const PEEK_SURFACES_SELECTOR = '#main-content, [data-attr="item-peek-drawer"]'

async function importPeekScene(sceneId: string): Promise<SceneExport<any> | null> {
    const config = ITEM_PEEK_SCENES[sceneId]
    const load = config?.load ?? appScenes[sceneId]
    if (!load) {
        return null
    }
    const module = await retryImport(() => load())
    return module?.scene ?? null
}

