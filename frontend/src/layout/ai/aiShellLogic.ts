/** Which PostHog AI implementation the Max scene renders when the sandbox flag is on. */
const PHAI_VIEW_MODE_KEY = 'posthog_ai_view_mode'

/** Why a chat input is disabled when `isMaxAvailable` is false. */
export const MAX_MISSING_KEYS_REASON = 'PostHog AI needs ANTHROPIC_API_KEY and OPENAI_API_KEY set on this instance'

/** Why the task composer is disabled when `isTaskRunnerAvailable` is false. */
export const TASK_RUNNER_MISSING_KEY_REASON = 'PostHog AI needs ANTHROPIC_API_KEY set on this instance'

