/**
 * The PostHog AI state the app shell reads on every page. It must stay light: the shell loads it eagerly,
 * so it must not import the Max scene or the posthog_ai run surface.
 */
export const aiShellLogic = kea<aiShellLogicType>([
    path(['layout', 'ai', 'aiShellLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], preflightLogic, ['preflight', 'isCloudOrDev']],
    })),
    actions({
        setPhaiViewMode: (mode: PhaiViewMode) => ({ mode }),
        askSidePanelMax: (prompt: string) => ({ prompt }),
        registerTool: (tool: ToolRegistration) => ({ tool }),
        deregisterTool: (key: string) => ({ key }),
    }),
    reducers({
        // The user's chosen implementation, persisted per device. Defaults to the new surface so a
        // flagged user lands there; `effectivePhaiView` collapses this to legacy when the flag is off.
        phaiViewMode: [
            'new' as PhaiViewMode,
            { persist: true, storageKey: PHAI_VIEW_MODE_KEY },
            {
                setPhaiViewMode: (_, { mode }) => mode,
            },
        ],
        // The tools of the scene on screen. Scenes register here, not in the Max logics, so a tool registered
        // before the Max chunk loads is still there when it does.
        registeredToolMap: [
            {} as Record<string, ToolRegistration>,
            {
                registerTool: (state, { tool }) => ({
                    ...state,
                    [tool.identifier]: tool,
                }),
                deregisterTool: (state, { key }) => {
                    const newState = { ...state }
                    delete newState[key]
                    return newState
                },
            },
        ],
    }),
    selectors({
        // On Cloud/dev both provider keys are always present. A self-hosted instance needs both keys:
        // the agent runs on Anthropic, and the conversation title comes from OpenAI. Without the title
        // the conversation API returns 404 for the new chat, so one key alone still breaks the chat.
        // A not-yet-loaded preflight (null) counts as available, so the "set the keys" state does not
        // flash before preflight resolves.
        isMaxAvailable: [
            (s) => [s.isCloudOrDev, s.preflight],
            (isCloudOrDev: boolean | undefined, preflight: PreflightStatus | null): boolean =>
                !preflight || !!isCloudOrDev || (!!preflight.anthropic_available && !!preflight.openai_available),
        ],
        // Tasks run on Anthropic and are titled through the gateway with a text fallback, so unlike the
        // legacy chat they need no OpenAI key.
        isTaskRunnerAvailable: [
            (s) => [s.isCloudOrDev, s.preflight],
            (isCloudOrDev: boolean | undefined, preflight: PreflightStatus | null): boolean =>
                !preflight || !!isCloudOrDev || !!preflight.anthropic_available,
        ],
        // Gates the new-vs-legacy toggle: only flagged users can switch, and the new surface only
        // exists for them.
        isPhaiSandboxFlagOn: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.PHAI_SANDBOX_MODE],
        ],
        // The implementation the Max scene actually renders: the user's choice while the flag is on,
        // always legacy otherwise (so non-flagged users are unaffected regardless of any stored value).
        effectivePhaiView: [
            (s) => [s.isPhaiSandboxFlagOn, s.phaiViewMode],
            (isPhaiSandboxFlagOn: boolean, phaiViewMode: PhaiViewMode): PhaiViewMode =>
                isPhaiSandboxFlagOn ? phaiViewMode : 'legacy',
        ],
        // For surfaces that route to either implementation, so the gate matches the keys the routed one needs.
        isAiAvailable: [
            (s) => [s.effectivePhaiView, s.isMaxAvailable, s.isTaskRunnerAvailable],
            (effectivePhaiView: PhaiViewMode, isMaxAvailable: boolean, isTaskRunnerAvailable: boolean): boolean =>
                effectivePhaiView === 'new' ? isTaskRunnerAvailable : isMaxAvailable,
        ],
    }),
    listeners({
        askSidePanelMax: ({ prompt }) => {
            newInternalTab(urls.ai(undefined, prompt))
        },
    }),
])
