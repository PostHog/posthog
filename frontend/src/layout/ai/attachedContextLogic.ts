function withoutPicks(
    pickedByChat: Record<string, AttachedContextItem[]>,
    chat: string,
    keys: Set<string>
): Record<string, AttachedContextItem[]> {
    const picks = pickedByChat[chat]
    return picks
        ? { ...pickedByChat, [chat]: picks.filter((item) => !keys.has(attachedContextItemKey(item))) }
        : pickedByChat
}

