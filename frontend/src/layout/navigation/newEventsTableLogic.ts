import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router, urlToAction } from 'kea-router'

import { getCookie } from 'lib/api'
import { userLogic } from 'scenes/userLogic'

import type { UserType } from '~/types'

// Temporary staff switch for the move from the events table to events_json. Remove the NewEventsTable* and
// newEventsTable* files here together with the cookie handling in posthog/models/event/new_events_schema.py when the
// migration is complete.
// pinned: NewEventsSchemaCookieMiddleware reads this cookie name and the value "1", and shared links carry the
// same name as a URL parameter
const NEW_EVENTS_SCHEMA = 'ph_new_events_schema'
const COOKIE_MAX_AGE_SECONDS = 7 * 24 * 60 * 60

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newEventsTableLogicValues {
    user: UserType | null // userLogic
    newEventsTableActive: boolean
    newEventsTableAvailable: boolean
    newEventsTableEnabled: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newEventsTableLogicActions {
    setNewEventsTable: (enabled: boolean) => {
        enabled: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface newEventsTableLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        newEventsTableAvailable: (user: UserType | null) => boolean
        newEventsTableActive: (newEventsTableAvailable: boolean, newEventsTableEnabled: boolean) => boolean
    }
}

export type newEventsTableLogicType = MakeLogicType<
    newEventsTableLogicValues,
    newEventsTableLogicActions,
    Record<string, any>,
    newEventsTableLogicMeta
>

export const newEventsTableLogic = kea<newEventsTableLogicType>([
    path(['layout', 'navigation', 'newEventsTableLogic']),
    connect(() => ({
        values: [userLogic, ['user']],
    })),
    actions({
        setNewEventsTable: (enabled: boolean) => ({ enabled }),
    }),
    reducers(() => ({
        newEventsTableEnabled: [
            getCookie(NEW_EVENTS_SCHEMA) === '1',
            {
                setNewEventsTable: (_, { enabled }) => enabled,
            },
        ],
    })),
    selectors({
        // The server honors the cookie only for these users, so the switch and the bar follow the same rule.
        newEventsTableAvailable: [
            (s) => [s.user],
            (user: UserType | null): boolean => !!user && (user.is_staff || user.is_impersonated),
        ],
        newEventsTableActive: [
            (s) => [s.newEventsTableAvailable, s.newEventsTableEnabled],
            (newEventsTableAvailable: boolean, newEventsTableEnabled: boolean): boolean =>
                newEventsTableAvailable && newEventsTableEnabled,
        ],
    }),
    listeners(() => ({
        setNewEventsTable: ({ enabled }) => {
            document.cookie = enabled
                ? `${NEW_EVENTS_SCHEMA}=1; path=/; max-age=${COOKIE_MAX_AGE_SECONDS}; SameSite=Lax`
                : `${NEW_EVENTS_SCHEMA}=; path=/; max-age=0; SameSite=Lax`
            // Results already in frontend state came from the other table, so reload to refetch everything.
            window.location.reload()
        },
    })),
    urlToAction(({ actions, values }) => ({
        '*': (_, searchParams, hashParams) => {
            const requested = searchParams[NEW_EVENTS_SCHEMA]
            if (requested === undefined || !values.newEventsTableAvailable) {
                return
            }
            // Strip the parameter before any reload, so the reloaded page cannot toggle the cookie again.
            const otherSearchParams = { ...searchParams }
            delete otherSearchParams[NEW_EVENTS_SCHEMA]
            router.actions.replace(router.values.location.pathname, otherSearchParams, hashParams)

            const enabled = String(requested) === '1'
            if (enabled !== values.newEventsTableEnabled) {
                actions.setNewEventsTable(enabled)
            }
        },
    })),
])
