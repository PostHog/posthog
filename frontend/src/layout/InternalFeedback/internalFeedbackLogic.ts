export interface WidgetPosition {
    x: number
    y: number
}

/** What the feedback is about. `element` and `identifier` are null for feedback about the whole page. */
export interface FeedbackTarget {
    element: HTMLElement | null
    identifier: string | null
    pageUrl: string
}

const DATA_ATTRIBUTES = ['data-attr']
const VIEWPORT_MARGIN = 8
// Matches the backend limit on the screenshot upload.
const MAX_SCREENSHOT_BYTES = 5 * 1024 * 1024

/** Keeps the bar fully on screen, also after the window shrinks below a saved position. */
export function clampToViewport(
    position: WidgetPosition,
    size: { width: number; height: number },
    viewport: { width: number; height: number }
): WidgetPosition {
    return {
        x: Math.max(VIEWPORT_MARGIN, Math.min(position.x, viewport.width - size.width - VIEWPORT_MARGIN)),
        y: Math.max(VIEWPORT_MARGIN, Math.min(position.y, viewport.height - size.height - VIEWPORT_MARGIN)),
    }
}

function isWidgetElement(element: Element): boolean {
    return !!element.closest(`[${INTERNAL_FEEDBACK_IGNORE_ATTR}]`)
}

/** Clicks on an icon land on its SVG parts, which are not HTML elements, so select the nearest HTML ancestor. */
function toSelectableElement(target: EventTarget | null): HTMLElement | null {
    let element = target instanceof Element ? target : null
    while (element && !(element instanceof HTMLElement)) {
        element = element.parentElement
    }
    return element && !isWidgetElement(element) ? element : null
}

function describeTarget(element: HTMLElement | null): FeedbackTarget {
    return {
        element,
        identifier: element ? elementToQuery(element, DATA_ATTRIBUTES) || element.tagName.toLowerCase() : null,
        // Read at select time: on an SPA the URL can change before the person saves.
        pageUrl: window.location.href,
    }
}

