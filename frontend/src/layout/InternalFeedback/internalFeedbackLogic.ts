export const internalFeedbackLogic = kea<internalFeedbackLogicType>([
    path(['layout', 'InternalFeedback', 'internalFeedbackLogic']),

    actions({
        hide: true,
        startInspecting: true,
        stopInspecting: true,
        startGeneralFeedback: () => ({ target: describeTarget(null) }),
        setHoverElement: (element: HTMLElement | null) => ({ element }),
        selectElement: (element: HTMLElement) => ({ target: describeTarget(element) }),
        clearSelection: true,
        setComment: (comment: string) => ({ comment }),
        setPosition: (position: WidgetPosition) => ({ position }),
        updateRects: true,
        submitFeedback: true,
        submitFeedbackSuccess: true,
        submitFeedbackFailure: (error: string) => ({ error }),
        clearJustSent: true,
    }),

    reducers({
        // Not persisted: closing hides the widget until the next page load.
        isHidden: [false, { hide: () => true }],
        // pinned: localStorage key via kea path + reducer name, renaming resets every saved position
        position: [
            null as WidgetPosition | null,
            { persist: true },
            {
                setPosition: (_, { position }) => position,
            },
        ],
        isInspecting: [
            false,
            {
                startInspecting: () => true,
                stopInspecting: () => false,
                selectElement: () => false,
                startGeneralFeedback: () => false,
                hide: () => false,
            },
        ],
        hoverElement: [
            null as HTMLElement | null,
            {
                setHoverElement: (_, { element }) => element,
                stopInspecting: () => null,
                selectElement: () => null,
                startGeneralFeedback: () => null,
                hide: () => null,
            },
        ],
        target: [
            null as FeedbackTarget | null,
            {
                selectElement: (_, { target }) => target,
                startGeneralFeedback: (_, { target }) => target,
                startInspecting: () => null,
                clearSelection: () => null,
                hide: () => null,
                submitFeedbackSuccess: () => null,
            },
        ],
        comment: [
            '',
            {
                setComment: (_, { comment }) => comment,
                startInspecting: () => '',
                startGeneralFeedback: () => '',
                clearSelection: () => '',
                hide: () => '',
                submitFeedbackSuccess: () => '',
            },
        ],
        submitError: [
            null as string | null,
            {
                submitFeedbackFailure: (_, { error }) => error,
                submitFeedback: () => null,
                setComment: () => null,
                selectElement: () => null,
                startGeneralFeedback: () => null,
                clearSelection: () => null,
                hide: () => null,
            },
        ],
        justSent: [
            false,
            {
                submitFeedbackSuccess: () => true,
                clearJustSent: () => false,
                startInspecting: () => false,
                startGeneralFeedback: () => false,
                hide: () => false,
            },
        ],
        isSubmitting: [
            false,
            {
                submitFeedback: () => true,
                submitFeedbackSuccess: () => false,
                submitFeedbackFailure: () => false,
            },
        ],
        rectUpdateCounter: [
            0,
            {
                updateRects: (state) => state + 1,
            },
        ],
    }),

    selectors({
        hoverElementRect: [
            (s) => [s.hoverElement, s.rectUpdateCounter],
            (hoverElement: HTMLElement | null): ElementRect | null =>
                hoverElement ? getRectForElement(hoverElement) : null,
        ],
        selectedElementRect: [
            (s) => [s.target, s.rectUpdateCounter],
            (target: FeedbackTarget | null): ElementRect | null =>
                target?.element ? getRectForElement(target.element) : null,
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        submitFeedback: async () => {
            const { target, comment } = values
            if (!target || !comment.trim()) {
                actions.submitFeedbackFailure('Write some feedback first.')
                return
            }
            // A failed screenshot must not lose the written feedback, so send without one.
            const captured: Blob | null = await (cache.screenshotPromise ?? Promise.resolve(null)).catch(() => null)
            // The backend refuses the whole request when the screenshot is too large, so drop it instead.
            const screenshot = captured && captured.size <= MAX_SCREENSHOT_BYTES ? captured : null
            try {
                await internalFeedbackCreate({
                    comment: comment.trim(),
                    page_url: target.pageUrl,
                    ...(target.identifier ? { element_identifier: target.identifier } : {}),
                    // A bare Blob uploads as "blob", and the backend ImageField rejects a name with no extension.
                    ...(screenshot
                        ? { screenshot: new File([screenshot], 'screenshot.jpg', { type: 'image/jpeg' }) }
                        : {}),
                })
            } catch (e) {
                actions.submitFeedbackFailure(
                    (e instanceof ApiError && e.detail) || "Couldn't send your feedback. Try again in a moment."
                )
                return
            }
            posthog.capture('internal feedback submitted', {
                has_screenshot: !!screenshot,
                is_whole_page: !target.element,
            })
            actions.submitFeedbackSuccess()
        },
        submitFeedbackSuccess: () => {
            cache.disposables.add(() => {
                const timeout = setTimeout(() => actions.clearJustSent(), 4000)
                return () => clearTimeout(timeout)
            }, 'justSentTimeout')
        },
        startInspecting: () => {
            posthog.capture('internal feedback inspect started')
        },
        selectElement: ({ target }) => {
            // Start right away, before the comment box takes focus and an open menu has a chance to close.
            cache.screenshotPromise = captureFeedbackScreenshot(target.element?.getBoundingClientRect() ?? null)
            cache.screenshotPromise.catch((e: unknown) => posthog.captureException(e))
        },
        startGeneralFeedback: () => {
            posthog.capture('internal feedback whole page started')
            cache.screenshotPromise = captureFeedbackScreenshot(null)
            cache.screenshotPromise.catch((e: unknown) => posthog.captureException(e))
        },
        clearSelection: () => {
            cache.screenshotPromise = null
        },
        hide: () => {
            cache.screenshotPromise = null
            posthog.capture('internal feedback closed')
        },
    })),

    events(({ actions, values, cache }) => ({
        afterMount: () => {
            // While inspecting, swallow presses on the page so a click selects instead of acting, and
            // so an open menu or popover does not close before it can be selected.
            const blockWhileInspecting = (e: Event): void => {
                const target = toSelectableElement(e.target)
                if (!values.isInspecting || !target) {
                    return
                }
                e.preventDefault()
                e.stopPropagation()
                if (e.type === 'click') {
                    actions.selectElement(target)
                }
            }
            const onMouseOver = (e: MouseEvent): void => {
                const target = toSelectableElement(e.target)
                if (values.isInspecting && target) {
                    actions.setHoverElement(target)
                }
            }
            const onViewportChange = (): void => {
                actions.updateRects()
            }
            // Enter or Space on a focused page control would activate it, so block it the same way as a press.
            const blockKeyActivationWhileInspecting = (e: KeyboardEvent): void => {
                if (values.isInspecting && (e.key === 'Enter' || e.key === ' ') && toSelectableElement(e.target)) {
                    e.preventDefault()
                    e.stopPropagation()
                }
            }
            const onKeyDown = (e: KeyboardEvent): void => {
                if (e.key !== 'Escape') {
                    return
                }
                if (values.isInspecting) {
                    actions.stopInspecting()
                } else if (values.target) {
                    actions.clearSelection()
                }
            }
            cache.disposables.add(() => {
                const blockedEvents = ['pointerdown', 'mousedown', 'mouseup', 'pointerup', 'click'] as const
                for (const type of blockedEvents) {
                    document.addEventListener(type, blockWhileInspecting, true)
                }
                document.addEventListener('keydown', blockKeyActivationWhileInspecting, true)
                document.addEventListener('mouseover', onMouseOver, true)
                document.addEventListener('scroll', onViewportChange, { capture: true, passive: true })
                window.addEventListener('resize', onViewportChange)
                window.addEventListener('keydown', onKeyDown)
                return () => {
                    for (const type of blockedEvents) {
                        document.removeEventListener(type, blockWhileInspecting, true)
                    }
                    document.removeEventListener('keydown', blockKeyActivationWhileInspecting, true)
                    document.removeEventListener('mouseover', onMouseOver, true)
                    document.removeEventListener('scroll', onViewportChange, { capture: true })
                    window.removeEventListener('resize', onViewportChange)
                    window.removeEventListener('keydown', onKeyDown)
                }
            }, 'documentListeners')
        },
    })),
])
