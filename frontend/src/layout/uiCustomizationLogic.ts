/**
 * Per-user UI customization, persisted as `User.ui_configuration` (see the UserUIConfiguration schema).
 * Resolution is fail-open: a null configuration or an absent key means "shown", so nothing disappears
 * while the user is loading and newly shipped sidebar elements show for everyone until hidden explicitly.
 */
export const uiCustomizationLogic = kea<uiCustomizationLogicType>([
    path(['layout', 'uiCustomizationLogic']),
    connect(() => ({
        values: [userLogic, ['user', 'userLoading'], featureFlagLogic, ['featureFlags']],
        actions: [userLogic, ['updateUser', 'updateUserSuccess']],
    })),
    actions({
        setSidebarSectionShown: (section: SidebarSectionKey, shown: boolean) => ({ section, shown }),
        setSidebarDensity: (density: SidebarDensity) => ({ density }),
        setSidebarItemShown: (item: SidebarItemKey, shown: boolean) => ({ item, shown }),
        setPendingUiConfiguration: (configuration: UserUIConfiguration | null) => ({ configuration }),
        clearPendingUiConfiguration: (configuration: UserUIConfiguration) => ({ configuration }),
        updateUiConfiguration: (
            configuration: UserUIConfiguration,
            successCallback?: () => void,
            failureCallback?: () => void
        ) => ({ configuration, successCallback, failureCallback }),
        completeStarredProductsSetup: true,
    }),
    reducers({
        // Optimistic copy held while the user PATCH is in flight, so toggles apply instantly.
        pendingUiConfiguration: [
            null as UserUIConfiguration | null,
            {
                setPendingUiConfiguration: (_, { configuration }) => configuration,
                clearPendingUiConfiguration: (state, { configuration }) => (state === configuration ? null : state),
                updateUserSuccess: (state, { payload }) => (payload?.user.ui_configuration === state ? null : state),
            },
        ],
    }),
    selectors({
        uiCustomizationEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.UI_CUSTOMIZATION],
        ],
        uiConfiguration: [
            (s) => [s.user, s.pendingUiConfiguration],
            (user: UserType | null, pendingUiConfiguration: UserUIConfiguration | null): UserUIConfiguration | null =>
                pendingUiConfiguration ?? user?.ui_configuration ?? null,
        ],
        // With the flag off, any stored configuration is ignored so the sidebar keeps its default layout.
        isSidebarSectionShown: [
            (s) => [s.uiConfiguration, s.uiCustomizationEnabled],
            (uiConfiguration: UserUIConfiguration | null, uiCustomizationEnabled: boolean) =>
                (section: SidebarSectionKey): boolean =>
                    !uiCustomizationEnabled || uiConfiguration?.sidebar?.sections?.[section]?.visible !== false,
        ],
        isSidebarItemShown: [
            (s) => [s.uiConfiguration, s.uiCustomizationEnabled],
            (uiConfiguration: UserUIConfiguration | null, uiCustomizationEnabled: boolean) =>
                (item: SidebarItemKey): boolean =>
                    !uiCustomizationEnabled || uiConfiguration?.sidebar?.items?.[item]?.visible !== false,
        ],
        // Unlike the visibility settings, this is read whether or not UI customization is on.
        starredProductsSetupCompleted: [
            (s) => [s.uiConfiguration],
            (uiConfiguration: UserUIConfiguration | null): boolean =>
                !!uiConfiguration?.sidebar?.starred_products_setup_completed,
        ],
        sidebarDensity: [
            (s) => [s.uiConfiguration, s.uiCustomizationEnabled],
            (uiConfiguration: UserUIConfiguration | null, uiCustomizationEnabled: boolean): SidebarDensity =>
                (uiCustomizationEnabled ? uiConfiguration?.sidebar?.density : null) ?? 'comfortable',
        ],
    }),
    listeners(({ actions, values }) => ({
        updateUiConfiguration: ({ configuration, successCallback, failureCallback }) => {
            actions.setPendingUiConfiguration(configuration)
            actions.updateUser({ ui_configuration: configuration }, successCallback, () => {
                actions.clearPendingUiConfiguration(configuration)
                failureCallback?.()
            })
        },
        setSidebarSectionShown: ({ section, shown }) => {
            const configuration = withSidebarSectionVisibility(values.uiConfiguration, section, shown)
            actions.updateUiConfiguration(configuration)
            posthog.capture('sidebar customization changed', {
                element_kind: 'section',
                element_key: section,
                shown,
            })
        },
        setSidebarItemShown: ({ item, shown }) => {
            const configuration = withSidebarItemVisibility(values.uiConfiguration, item, shown)
            actions.updateUiConfiguration(configuration)
            posthog.capture('sidebar customization changed', {
                element_kind: 'item',
                element_key: item,
                shown,
            })
        },
        setSidebarDensity: ({ density }) => {
            const configuration = withSidebarPatch(values.uiConfiguration, { density })
            actions.updateUiConfiguration(configuration)
            posthog.capture('sidebar customization changed', {
                element_kind: 'density',
                element_key: density,
            })
        },
        completeStarredProductsSetup: () => {
            const configuration = withSidebarPatch(values.uiConfiguration, { starred_products_setup_completed: true })
            actions.updateUiConfiguration(configuration)
        },
    })),
])
