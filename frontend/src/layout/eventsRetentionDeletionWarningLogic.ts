export const eventsRetentionDeletionWarningLogic = kea<eventsRetentionDeletionWarningLogicType>([
    path(['layout', 'eventsRetentionDeletionWarningLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        snooze: true,
        snoozeTeam: (teamId: number, until: string) => ({ teamId, until }),
    }),
    loaders(({ values }) => ({
        retention: [
            null as EventsRetentionApi | null,
            {
                loadRetention: async () =>
                    values.currentTeamId === null
                        ? null
                        : (await eventsRetentionRetrieve(String(values.currentTeamId))) || null,
            },
        ],
        scheduledDeletion: [
            null as ScheduledEventsDeletedApi | null,
            {
                loadScheduledDeletion: async () =>
                    values.currentTeamId === null
                        ? null
                        : await eventsRetentionScheduledDeletionCount(String(values.currentTeamId)),
            },
        ],
    })),
    reducers({
        snoozedUntilByTeam: [
            {} as Record<number, string>,
            { persist: true },
            {
                snoozeTeam: (state, { teamId, until }) => ({ ...state, [teamId]: until }),
            },
        ],
    }),
    selectors({
        defaultDeletionScheduled: [
            (s) => [s.retention],
            (retention: EventsRetentionApi | null): boolean =>
                !!retention &&
                retention.project_retention_months === null &&
                retention.organization_retention_months === null &&
                retention.default_period_deletes &&
                retention.next_deletion_on !== null,
        ],
        warning: [
            (s) => [s.defaultDeletionScheduled, s.retention, s.scheduledDeletion],
            (
                defaultDeletionScheduled: boolean,
                retention: EventsRetentionApi | null,
                scheduledDeletion: ScheduledEventsDeletedApi | null
            ): EventsRetentionDeletionWarning | null => {
                if (
                    !defaultDeletionScheduled ||
                    !retention ||
                    !scheduledDeletion?.deletes_on ||
                    !scheduledDeletion.deletes_before ||
                    scheduledDeletion.events_deleted === 0
                ) {
                    return null
                }
                const events = scheduledDeletion.events_deleted === 1 ? 'event' : 'events'
                return {
                    title: `Events older than ${retentionPeriodLabel(retention.default_retention_months)} will be deleted on ${dayjs(scheduledDeletion.deletes_on).format('MMM D')}`,
                    description: `That's ${compactNumber(scheduledDeletion.events_deleted)} ${events} in this project from before ${dayjs(scheduledDeletion.deletes_before).format('MMM D, YYYY')}.`,
                }
            },
        ],
        isSnoozed: [
            (s) => [s.snoozedUntilByTeam, s.currentTeamId],
            (snoozedUntilByTeam: Record<number, string>, currentTeamId: number | null): boolean => {
                const until = currentTeamId === null ? undefined : snoozedUntilByTeam[currentTeamId]
                return !!until && dayjs(until).isAfter(dayjs())
            },
        ],
        alertVisible: [
            (s) => [s.warning, s.isSnoozed],
            (warning: EventsRetentionDeletionWarning | null, isSnoozed: boolean): boolean => !!warning && !isSnoozed,
        ],
    }),
    listeners(({ actions, values }) => ({
        [teamLogic.actionTypes.loadCurrentTeamSuccess]: () => {
            actions.loadRetention()
        },
        loadRetentionSuccess: () => {
            if (values.defaultDeletionScheduled) {
                actions.loadScheduledDeletion()
            }
        },
        snooze: () => {
            if (values.currentTeamId !== null) {
                actions.snoozeTeam(values.currentTeamId, dayjs().add(1, 'month').toISOString())
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRetention()
    }),
])
