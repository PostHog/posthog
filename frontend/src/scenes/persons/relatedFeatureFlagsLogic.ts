export const relatedFeatureFlagsLogic = kea<relatedFeatureFlagsLogicType>([
    path(['scenes', 'persons', 'relatedFeatureFlagsLogic']),
    props(
        {} as {
            distinctId: string | null
            groupTypeIndex?: number
            groups?: { [key: string]: string }
        }
    ),
    key((props) => `${props.distinctId}`),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        setFilters: (filters: Partial<RelatedFlagsFilters>, replace?: boolean) => ({ filters, replace }),
        setPage: (page: number) => ({ page }),
        loadRelatedFeatureFlags: true,
    }),
    loaders(({ values, props, actions }) => ({
        featureFlags: [
            { results: [], count: 0, offset: 0 } as FeatureFlagsResult,
            {
                loadFeatureFlags: async (_: void, breakpoint) => {
                    const type =
                        values.filters.type === FeatureFlagReleaseType.ReleaseToggle
                            ? 'boolean'
                            : values.filters.type === FeatureFlagReleaseType.Variants
                              ? 'multivariant'
                              : undefined
                    const params = {
                        limit: FLAGS_PER_PAGE,
                        offset: (values.currentPage - 1) * FLAGS_PER_PAGE,
                        search: values.searchTerm.trim() || undefined,
                        active: values.filters.active,
                        type,
                    }
                    const response = await api.get(
                        `api/projects/${values.currentProjectId}/feature_flags/?${toParams(params)}`
                    )
                    breakpoint()

                    return { ...response, offset: params.offset }
                },
            },
        ],
        relatedFeatureFlags: [
            null as RelatedFeatureFlagResponse | null,
            {
                loadRelatedFeatureFlags: async () => {
                    actions.loadFeatureFlags()
                    const response = await api.get(
                        `api/projects/${values.currentProjectId}/feature_flags/evaluation_reasons?${toParams({
                            ...(props.distinctId ? { distinct_id: props.distinctId } : {}),
                            ...(props.groups ? { groups: props.groups } : {}),
                        })}`
                    )
                    return response
                },
            },
        ],
    })),
    reducers({
        searchTerm: [
            '',
            {
                setSearchTerm: (_, { searchTerm }) => searchTerm,
            },
        ],
        currentPage: [
            1,
            {
                setSearchTerm: () => 1,
                setFilters: (state, { filters, replace }) =>
                    replace || 'type' in filters || 'active' in filters ? 1 : state,
                setPage: (_, { page }) => page,
            },
        ],
        filters: [
            {} as Partial<RelatedFlagsFilters>,
            {
                setFilters: (state, { filters, replace }) => {
                    if (replace) {
                        return { ...filters }
                    }
                    return { ...state, ...filters }
                },
            },
        ],
        // Track whether the evaluation_reasons request failed so the table can show a
        // retry affordance instead of rendering as an empty (looks like "no flags") list.
        loadError: [
            false,
            {
                loadRelatedFeatureFlags: () => false,
                loadRelatedFeatureFlagsSuccess: () => false,
                loadRelatedFeatureFlagsFailure: () => true,
            },
        ],
    }),
    selectors(({ props, selectors }) => ({
        isLoading: [
            () => [selectors.relatedFeatureFlagsLoading, selectors.featureFlagsLoading],
            (relatedLoading: boolean, featureFlagsLoading: boolean): boolean => {
                return relatedLoading || featureFlagsLoading
            },
        ],
        mappedRelatedFeatureFlags: [
            (selectors) => [selectors.relatedFeatureFlags, selectors.featureFlags],
            (
                relatedFlags: RelatedFeatureFlagResponse | null,
                featureFlags: import('scenes/feature-flags/featureFlagsLogic').FeatureFlagsResult
            ): RelatedFeatureFlag[] => {
                if (relatedFlags && featureFlags) {
                    let flags = featureFlags.results
                        .map((flag) => ({ ...relatedFlags[flag.key], ...flag }))
                        .filter((flag) => flag.evaluation !== undefined)

                    // return related feature flags for group property targeting or person property targeting, but not both
                    if (props.groupTypeIndex !== undefined && props.groups && Object.keys(props.groups).length > 0) {
                        flags = flags.filter(
                            (flag) =>
                                flag.filters.aggregation_group_type_index != null &&
                                flag.filters.aggregation_group_type_index === props.groupTypeIndex
                        )
                    } else {
                        flags = flags.filter((flag) => flag.filters.aggregation_group_type_index == null)
                    }

                    return flags
                }
                return []
            },
        ],
        filteredMappedFlags: [
            (selectors) => [selectors.mappedRelatedFeatureFlags, selectors.filters],
            (featureFlags: RelatedFeatureFlag[], filters: Partial<RelatedFlagsFilters>) => {
                let filteredFlags = featureFlags

                const { reason } = filters
                if (reason) {
                    filteredFlags = filteredFlags.filter((flag) =>
                        reason === 'not matched'
                            ? flag.evaluation.reason !== FeatureFlagMatchReason.ConditionMatch
                            : flag.evaluation.reason === FeatureFlagMatchReason.ConditionMatch
                    )
                }
                return filteredFlags
            },
        ],
        pagination: [
            () => [selectors.featureFlags, selectors.currentPage, selectors.loadError],
            (
                featureFlags: FeatureFlagsResult,
                currentPage: number,
                loadError: boolean
            ): PaginationManual | undefined => {
                if (loadError) {
                    return undefined
                }
                return {
                    controlled: true,
                    pageSize: FLAGS_PER_PAGE,
                    currentPage,
                    entryCount: featureFlags.count,
                }
            },
        ],
    })),
    listeners(({ actions }) => ({
        setSearchTerm: async (_, breakpoint) => {
            await breakpoint(300)
            actions.loadFeatureFlags()
        },
        setFilters: ({ filters, replace }) => {
            if (replace || 'type' in filters || 'active' in filters) {
                actions.loadFeatureFlags()
            }
        },
        setPage: () => actions.loadFeatureFlags(),
    })),
    urlToAction(({ actions }) => ({
        [urls.personByUUID('*', false)]: async (_, searchParams) => {
            const page = searchParams['page']
            if (page !== undefined) {
                actions.setPage(parseInt(page))
            }
        },
    })),
    events(({ actions }) => ({
        afterMount: () => {
            actions.loadRelatedFeatureFlags()
        },
    })),
])
