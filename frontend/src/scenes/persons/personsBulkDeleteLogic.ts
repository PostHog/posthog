export type personsBulkDeleteLogicType = MakeLogicType<
    personsBulkDeleteLogicValues,
    personsBulkDeleteLogicActions,
    Record<string, any>,
    personsBulkDeleteLogicMeta
>

export const personsBulkDeleteLogic = kea<personsBulkDeleteLogicType>([
    path(['scenes', 'persons', 'personsBulkDeleteLogic']),

    actions({
        openModal: (filters: PersonsBulkDeleteFilters) => ({ filters }),
        closeModal: () => ({}),
        setDeleteEvents: (deleteEvents: boolean) => ({ deleteEvents }),
        setDeleteRecordings: (deleteRecordings: boolean) => ({ deleteRecordings }),
        setConfirmationText: (confirmationText: string) => ({ confirmationText }),
        setDeletedCount: (deletedCount: number) => ({ deletedCount }),
        setIsDeleting: (isDeleting: boolean) => ({ isDeleting }),
        deleteMatchingPersons: () => ({}),
    }),

    reducers({
        filters: [
            null as PersonsBulkDeleteFilters | null,
            {
                openModal: (_, { filters }) => filters,
                closeModal: () => null,
            },
        ],
        deleteEvents: [
            false,
            {
                setDeleteEvents: (_, { deleteEvents }) => deleteEvents,
                closeModal: () => false,
            },
        ],
        deleteRecordings: [
            false,
            {
                setDeleteRecordings: (_, { deleteRecordings }) => deleteRecordings,
                closeModal: () => false,
            },
        ],
        confirmationText: [
            '',
            {
                setConfirmationText: (_, { confirmationText }) => confirmationText,
                openModal: () => '',
                closeModal: () => '',
            },
        ],
        deletedCount: [
            0,
            {
                setDeletedCount: (_, { deletedCount }) => deletedCount,
                openModal: () => 0,
            },
        ],
        isDeleting: [
            false,
            {
                setIsDeleting: (_, { isDeleting }) => isDeleting,
                closeModal: () => false,
            },
        ],
    }),

    loaders(({ values }) => ({
        matchCount: [
            null as number | null,
            {
                loadMatchCount: async () => {
                    if (!values.filters) {
                        return null
                    }
                    const response = await api.persons.bulkDelete({
                        ...toRequestPayload(values.filters),
                        dry_run: true,
                    })
                    return response.persons_found
                },
            },
        ],
    })),

    selectors({
        isConfirmed: [
            (s) => [s.confirmationText],
            (confirmationText: string): boolean => confirmationText === DELETE_CONFIRMATION_TEXT,
        ],
    }),

    listeners(({ actions, values }) => ({
        openModal: () => {
            actions.loadMatchCount()
        },
        // Deliberately no breakpoint in the loop below: once persons start being deleted we want the
        // sweep to run to completion rather than abandon it half-done on the next dispatched action.
        deleteMatchingPersons: async () => {
            const filters = values.filters
            if (!filters) {
                return
            }
            actions.setIsDeleting(true)
            let deleted = 0
            let emptyPages = 0
            try {
                for (;;) {
                    const response = await api.persons.bulkDelete({
                        ...toRequestPayload(filters),
                        delete_events: values.deleteEvents,
                        delete_recordings: values.deleteRecordings,
                    })
                    deleted += response.persons_deleted
                    actions.setDeletedCount(deleted)
                    emptyPages = response.persons_deleted === 0 ? emptyPages + 1 : 0
                    if (!response.has_more || emptyPages >= MAX_EMPTY_PAGES) {
                        break
                    }
                }
            } catch (error: any) {
                actions.setIsDeleting(false)
                lemonToast.error(
                    `Deleted ${deleted} ${deleted === 1 ? 'person' : 'persons'} before this failed: ${
                        error.detail || error.message || 'unknown error'
                    }. Run it again to delete the rest.`
                )
                return
            }
            posthog.capture('bulk delete persons', {
                persons_deleted: deleted,
                delete_events: values.deleteEvents,
                delete_recordings: values.deleteRecordings,
            })
            actions.closeModal()
            lemonToast.success(`Deleted ${deleted} ${deleted === 1 ? 'person' : 'persons'}`)
            dataNodeCollectionLogic.findMounted({ key: PERSONS_DATA_NODE_COLLECTION_KEY })?.actions.reloadAll()
        },
    })),
])
