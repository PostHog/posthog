import { MakeLogicType, actions, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'

import { dataNodeCollectionLogic } from '~/queries/nodes/DataNode/dataNodeCollectionLogic'
import { AnyPropertyFilter } from '~/types'

import type { PersonBulkDeleteFilterApi } from 'products/persons/frontend/generated/api.schemas'

import { PERSONS_QUERY_UNIQUE_KEY } from './personsSceneLogic'

/** DataTable derives its data node collection key from the `uniqueKey` it is rendered with. */
const PERSONS_DATA_NODE_COLLECTION_KEY = `DataNode.${PERSONS_QUERY_UNIQUE_KEY}`

/** Every call deletes one page, so we loop. A page that matches but deletes nothing means the
 * remaining matches are already gone from Postgres and we'd otherwise loop forever. */
const MAX_EMPTY_PAGES = 3

export interface PersonsBulkDeleteFilters {
    properties: AnyPropertyFilter[]
    search?: string
}

export const DELETE_CONFIRMATION_TEXT = 'delete'

/** The endpoint takes the same person filters the table does, minus the shapes it won't delete by. */
function toRequestPayload(filters: PersonsBulkDeleteFilters): {
    properties: PersonBulkDeleteFilterApi[]
    search?: string
} {
    return {
        properties: filters.properties.map((filter) => ({
            key: String(filter.key),
            type: filter.type,
            operator: 'operator' in filter ? (filter.operator ?? undefined) : undefined,
            value: 'value' in filter ? (filter.value as PersonBulkDeleteFilterApi['value']) : undefined,
        })),
        ...(filters.search ? { search: filters.search } : {}),
    }
}

