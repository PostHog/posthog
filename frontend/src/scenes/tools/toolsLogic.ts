import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'

import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { getProductAccessDisabledReason } from 'lib/utils/accessControlUtils'

import { todayShellLogic } from '~/layout/today/todayShellLogic'
import { isWarehouseToolHref } from '~/layout/today/todayWarehouseItems'
import { getTreeItemsMetadata, getTreeItemsProducts } from '~/products'
import { FileSystemImport } from '~/queries/schema/schema-general'

import { ToolGroup, groupTools, isToolItem, toolLabel } from './toolsUtils'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface toolsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    search: string
    todayWarehouseEnabled: boolean // todayShellLogic
    toolGroups: ToolGroup[]
    tools: FileSystemImport[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface toolsLogicActions {
    setSearch: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface toolsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        tools: (featureFlags: FeatureFlagsSet, todayWarehouseEnabled: boolean) => FileSystemImport[]
        toolGroups: (tools: FileSystemImport[], search: string) => ToolGroup[]
    }
}

export type toolsLogicType = MakeLogicType<toolsLogicValues, toolsLogicActions, Record<string, any>, toolsLogicMeta>

export const toolsLogic = kea<toolsLogicType>([
    path(['scenes', 'tools', 'toolsLogic']),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags'], todayShellLogic, ['todayWarehouseEnabled']] })),
    actions({ setSearch: (search: string) => ({ search }) }),
    reducers({ search: ['', { setSearch: (_, { search }) => search }] }),
    selectors({
        tools: [
            (s) => [s.featureFlags, s.todayWarehouseEnabled],
            (featureFlags: FeatureFlagsSet, todayWarehouseEnabled: boolean): FileSystemImport[] => {
                const seen = new Set<string>()
                return [...getTreeItemsProducts(), ...getTreeItemsMetadata()]
                    .filter((item) => {
                        if (
                            !item.href ||
                            !isToolItem(item) ||
                            seen.has(item.href) ||
                            // The rail's warehouse menu is the only home for these under the rail navigation.
                            (todayWarehouseEnabled && isWarehouseToolHref(item.href)) ||
                            (item.flag && !featureFlags[item.flag as keyof FeatureFlagsSet]) ||
                            getProductAccessDisabledReason(item)
                        ) {
                            return false
                        }
                        seen.add(item.href)
                        return true
                    })
                    .sort((first, second) => toolLabel(first).localeCompare(toolLabel(second)))
            },
        ],
        toolGroups: [
            (s) => [s.tools, s.search],
            (tools: FileSystemImport[], search: string): ToolGroup[] => groupTools(tools, search),
        ],
    }),
])
