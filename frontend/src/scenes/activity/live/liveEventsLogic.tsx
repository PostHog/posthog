const EVENTS_ENDPOINT = 'events'

export const LIVE_EVENTS_SUPPORTED_OPERATORS: PropertyOperator[] = [
    PropertyOperator.Exact,
    PropertyOperator.IsNot,
    PropertyOperator.IContains,
    PropertyOperator.NotIContains,
    PropertyOperator.Regex,
    PropertyOperator.NotRegex,
    PropertyOperator.GreaterThan,
    PropertyOperator.GreaterThanOrEqual,
    PropertyOperator.LessThan,
    PropertyOperator.LessThanOrEqual,
    PropertyOperator.IsSet,
    PropertyOperator.IsNotSet,
]

export interface LiveStreamError {
    message: string
    /** True while `api.stream` reconnects on its own. False once the stream is dead and needs a manual retry. */
    retrying: boolean
}

const UNAVAILABLE_ERROR: LiveStreamError = {
    message: 'Live events are not available for this project. Reload the page, and contact us if it keeps happening.',
    retrying: false,
}

function describeStreamError(error: unknown): LiveStreamError {
    if (error instanceof RateLimitError) {
        return { message: 'The live event stream is rate limited. Wait a moment, then try again.', retrying: false }
    }
    // `api.stream` aborts the connection after a non-ok response, so nothing reconnects on its own here.
    if (error instanceof ApiError && error.status) {
        if (error.status === 401 || error.status === 403) {
            return {
                message:
                    'This project cannot read the live event stream. Reload the page, and contact us if it keeps happening.',
                retrying: false,
            }
        }
        return {
            message: `The live event stream failed with error ${error.status}. Try again, and contact us if it keeps happening.`,
            retrying: false,
        }
    }
    return { message: 'Lost the connection to the live event stream. Trying to reconnect.', retrying: true }
}

