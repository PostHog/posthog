import { MakeLogicType, beforeUnmount, connect, kea, key, listeners, path, selectors } from 'kea'

import { lemonToast } from '@posthog/lemon-ui'

import { sceneConfigurations } from 'scenes/scenes'
import { Scene } from 'scenes/sceneTypes'

import { Breadcrumb } from '~/types'

import { liveEventsLogic } from './liveEventsLogic'

const ERROR_TOAST_ID_PREFIX = 'live-stream-error'

// lemonToast remembers a dismissed id and swallows the next toast created under it, so reusing one
// id would silence every error that follows a healthy connection. Each error episode gets its own.
let errorToastSequence = 0

function dismissErrorToast(cache: Record<string, any>): void {
    if (cache.errorToastId) {
        lemonToast.dismiss(cache.errorToastId)
        cache.errorToastId = null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface liveEventsTableSceneLogicValues {
    breadcrumbs: Breadcrumb[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface liveEventsTableSceneLogicActions {
    pauseStream: () => {
        value: true
    } // liveEventsLogic
    streamConnected: () => {
        value: true
    } // liveEventsLogic
    streamErrored: (error: import('./liveEventsLogic').LiveStreamError) => {
        error: import('./liveEventsLogic').LiveStreamError
    } // liveEventsLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface liveEventsTableSceneLogicMeta {
    key: string
}

export type liveEventsTableSceneLogicType = MakeLogicType<
    liveEventsTableSceneLogicValues,
    liveEventsTableSceneLogicActions,
    Record<string, any>,
    liveEventsTableSceneLogicMeta
>

export const liveEventsTableSceneLogic = kea<liveEventsTableSceneLogicType>([
    key(() => 'scene'),
    path((key) => ['scenes', 'activity', 'live-events', 'liveEventsTableSceneLogic', key]),
    connect(() => ({
        actions: [liveEventsLogic, ['streamErrored', 'streamConnected', 'pauseStream']],
    })),
    selectors(() => ({
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: Scene.LiveEvents,
                    name: sceneConfigurations[Scene.LiveEvents].name,
                    iconType: sceneConfigurations[Scene.LiveEvents].iconType,
                },
            ],
        ],
    })),
    // The toast lives here rather than in liveEventsLogic because onboarding mounts that logic
    // too, and a stream that cannot connect yet is expected there rather than worth an error.
    listeners(({ cache }) => ({
        streamErrored: ({ error }) => {
            // A reconnect that fails for a new reason must change what the toast says, and a second
            // error() under a live id is dropped as a duplicate.
            if (cache.errorToastId && lemonToast.isActive(cache.errorToastId)) {
                lemonToast.updateToError(cache.errorToastId, error.message)
                return
            }
            cache.errorToastId = `${ERROR_TOAST_ID_PREFIX}-${++errorToastSequence}`
            lemonToast.error(error.message, { toastId: cache.errorToastId, autoClose: false })
        },
        streamConnected: () => {
            dismissErrorToast(cache)
        },
        // Pausing stops every reconnect, so a toast promising one would be wrong from the moment
        // it is read.
        pauseStream: () => {
            dismissErrorToast(cache)
        },
    })),
    beforeUnmount(({ cache }) => {
        dismissErrorToast(cache)
    }),
])
