export const flagCallsSceneLogic = kea<flagCallsSceneLogicType>([
    key(() => 'scene'),
    path((key) => ['scenes', 'activity', 'explore', 'flagCallsSceneLogic', key]),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeam'],
            filterTestAccountsDefaultsLogic,
            ['filterTestAccountsDefault'],
            tabUiStateLogic,
            ['savedQueryFor'],
        ],
        actions: [tabUiStateLogic, ['setSavedQueryForTab']],
    })),

    actions({ setQuery: (query: Node) => ({ query: pinToFlagCalls(query) }) }),
    reducers({ savedQuery: [null as FlagCallsQuery | null, { setQuery: (_, { query }) => query }] }),
    listeners(({ actions, values }) => ({
        setQuery: ({ query }) => {
            const isDefault = !query || objectsEqual(query, values.defaultQuery)
            actions.setSavedQueryForTab(undefined, SAVED_QUERY_KEY, isDefault ? null : query)
        },
    })),
    selectors({
        defaultQuery: [
            (s) => [s.currentTeam, s.filterTestAccountsDefault],
            (currentTeam: TeamPublicType | TeamType | null, filterTestAccountsDefault: boolean): FlagCallsQuery =>
                applyTestAccountFilter(getDefaultFlagCallsSceneQuery(), currentTeam, filterTestAccountsDefault),
        ],
        query: [
            (s) => [s.savedQuery, s.defaultQuery],
            (savedQuery: FlagCallsQuery | null, defaultQuery: FlagCallsQuery): FlagCallsQuery =>
                savedQuery || defaultQuery,
        ],
        reachesPastRetention: [
            (s) => [s.currentTeam, s.query],
            (currentTeam: TeamPublicType | TeamType | null, query: FlagCallsQuery): boolean =>
                flagCallsListReachesPastRetention(currentTeam, query.source),
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: Scene.ExploreFlagCalls,
                    name: sceneConfigurations[Scene.ExploreFlagCalls].name,
                    iconType: sceneConfigurations[Scene.ExploreFlagCalls].iconType || 'default_icon_type',
                },
            ],
        ],
    }),
    trackedActionToUrl(({ values }) => ({
        setQuery: () => [
            urls.activity(ActivityTab.ExploreFlagCalls),
            {},
            objectsEqual(values.query, values.defaultQuery) ? {} : { q: values.query },
            { replace: true },
        ],
    })),

    urlToAction(({ actions, values }) => {
        const flagCallsQueryHandler: UrlToActionPayload[keyof UrlToActionPayload] = (
            _,
            __,
            { q: queryParam }
        ): void => {
            if (equal(queryParam, values.query)) {
                return
            }
            if (!queryParam) {
                const target = values.savedQueryFor(undefined, SAVED_QUERY_KEY) ?? values.defaultQuery
                if (!objectsEqual(values.query, target)) {
                    actions.setQuery(target)
                }
                return
            }
            if (typeof queryParam !== 'object') {
                lemonToast.error('Invalid query in URL')
                console.error({ queryParam })
                return
            }
            actions.setQuery(queryParam)
        }

        return {
            [urls.activity(ActivityTab.ExploreFlagCalls)]: flagCallsQueryHandler,
        }
    }),
])
