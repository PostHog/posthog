// pinned: tabUiStateLogic persists the tab's query under this key
const SAVED_QUERY_KEY = 'flag-calls'

export type FlagCallsQuery = DataTableNode & { source: EventsQuery }

const FLAG_CALLS_COLUMNS = [
    '*',
    'properties.$feature_flag',
    'properties.$feature_flag_response',
    PERSON_DISPLAY_NAME_COLUMN_NAME,
    'coalesce(properties.$current_url, properties.$screen_name) -- Url / Screen',
    'properties.$lib',
    'timestamp',
]

export const getDefaultFlagCallsSceneQuery = (): FlagCallsQuery => ({
    kind: NodeKind.DataTableNode,
    full: true,
    source: {
        kind: NodeKind.EventsQuery,
        select: FLAG_CALLS_COLUMNS,
        event: FEATURE_FLAG_CALLED_EVENT,
        orderBy: ['timestamp DESC'],
        after: '-24h',
    },
    propertiesViaUrl: true,
    showEventFilter: false,
    // Reset to defaults in the column configurator restores these instead of the generic event columns.
    defaultColumns: FLAG_CALLS_COLUMNS,
    showPersistentColumnConfigurator: true,
    // pinned: the saved column configuration is stored under this key
    contextKey: 'activity-flag-calls',
})

/**
 * For a team whose events table holds no new flag calls, a query that the runner sends to the events table lists
 * nothing. Returns null for a query this tab can't show.
 */
function pinToFlagCalls(query: Node): FlagCallsQuery | null {
    if (!isDataTableNode(query) || !isEventsQuery(query.source)) {
        return null
    }
    const pinned: FlagCallsQuery = {
        ...query,
        showEventFilter: false,
        defaultColumns: FLAG_CALLS_COLUMNS,
        source: {
            ...query.source,
            event: FEATURE_FLAG_CALLED_EVENT,
            events: undefined,
            actionId: undefined,
            actionSteps: undefined,
            source: undefined,
        },
    }
    // The URL holds the query as JSON, which drops keys set to undefined. The stored query matches that form.
    const stored = JSON.parse(JSON.stringify(pinned)) as FlagCallsQuery
    return listsOnlyFlagCalls(stored.source) ? stored : null
}

