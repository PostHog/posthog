/** How far back the empty-state probe looks for events the current query window excludes. */
const PROBE_WINDOW = '-90d'

export interface HiddenEventsProbe {
    /** Timestamp of the newest matching event outside the query window, if there is one. */
    latestOutsideWindow: string | null
    /** True when the team's test account filter is what removed the rows. */
    hiddenByTestAccountFilter: boolean
}

/** The probe resolves to this when it finds nothing, so a null value always means "not resolved yet". */
const NOTHING_HIDDEN: HiddenEventsProbe = { latestOutsideWindow: null, hiddenByTestAccountFilter: false }

function probeSource(source: EventsQuery, overrides: Partial<EventsQuery>): EventsQuery {
    return {
        ...source,
        select: ['timestamp'],
        orderBy: ['timestamp DESC'],
        limit: 1,
        offset: undefined,
        ...overrides,
    }
}

