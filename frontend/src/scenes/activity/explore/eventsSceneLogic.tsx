export const eventsSceneLogic = kea<eventsSceneLogicType>([
    key(() => 'scene'),
    path((key) => ['scenes', 'events', 'eventsSceneLogic', key]),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeam'],
            featureFlagLogic,
            ['featureFlags'],
            filterTestAccountsDefaultsLogic,
            ['filterTestAccountsDefault'],
            tabUiStateLogic,
            ['savedQueryFor'],
        ],
        actions: [tabUiStateLogic, ['setSavedQueryForTab']],
    })),

    actions({
        setQuery: (query: Node) => ({ query }),
        probeForHiddenEvents: true,
        widenToHiddenEvents: true,
        dropTestAccountFilter: true,
    }),
    reducers({ savedQuery: [null as Node | null, { setQuery: (_, { query }) => query }] }),
    loaders(({ values }) => ({
        hiddenEventsProbe: [
            null as HiddenEventsProbe | null,
            {
                probeForHiddenEvents: async (_, breakpoint): Promise<HiddenEventsProbe> => {
                    await breakpoint(300)
                    const source = values.eventsQuerySource
                    if (!source) {
                        return NOTHING_HIDDEN
                    }

                    try {
                        const [outsideWindow, withoutTestFilter] = await Promise.all([
                            api.query(probeSource(source, { after: PROBE_WINDOW, before: undefined })),
                            source.filterTestAccounts
                                ? api.query(probeSource(source, { filterTestAccounts: false }))
                                : Promise.resolve(null),
                        ])
                        breakpoint()

                        return {
                            latestOutsideWindow: outsideWindow.results?.[0]?.[0] ?? null,
                            hiddenByTestAccountFilter: (withoutTestFilter?.results?.length ?? 0) > 0,
                        }
                    } catch (e: any) {
                        if (isBreakpoint(e)) {
                            throw e
                        }
                        // The generic copy is a better answer than a spinner that never resolves.
                        return NOTHING_HIDDEN
                    }
                },
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        setQuery: ({ query }) => {
            const isDefault = objectsEqual(query, values.defaultQuery)
            actions.setSavedQueryForTab(undefined, 'events', isDefault ? null : query)
        },
        probeForHiddenEventsSuccess: ({ hiddenEventsProbe }) => {
            if (!hiddenEventsProbe?.latestOutsideWindow && !hiddenEventsProbe?.hiddenByTestAccountFilter) {
                return
            }
            posthog.capture('activity empty state explained', {
                outside_time_window: !!hiddenEventsProbe.latestOutsideWindow,
                hidden_by_test_account_filter: hiddenEventsProbe.hiddenByTestAccountFilter,
            })
        },
        widenToHiddenEvents: () => {
            const latest = values.hiddenEventsProbe?.latestOutsideWindow
            const source = values.eventsQuerySource
            if (!latest || !source) {
                return
            }
            posthog.capture('activity empty state widened')
            const widened: DataTableNode = {
                ...(values.query as DataTableNode),
                source: { ...source, after: dayjs(latest).subtract(1, 'hour').toISOString(), before: undefined },
            }
            actions.setQuery(widened)
        },
        dropTestAccountFilter: () => {
            const source = values.eventsQuerySource
            if (!source) {
                return
            }
            posthog.capture('activity empty state test filter dropped')
            const unfiltered: DataTableNode = {
                ...(values.query as DataTableNode),
                source: { ...source, filterTestAccounts: false },
            }
            actions.setQuery(unfiltered)
        },
    })),
    selectors({
        defaultQuery: [
            (s) => [s.currentTeam, s.filterTestAccountsDefault],
            (
                currentTeam: null | import('~/types').TeamPublicType | import('~/types').TeamType,
                filterTestAccountsDefault: boolean
            ): DataTableNode => {
                const defaultSourceForTeam = currentTeam && getDefaultEventsQueryForTeam(currentTeam)
                const defaultForScene = getDefaultEventsSceneQuery()
                const base = defaultSourceForTeam
                    ? { ...defaultForScene, source: defaultSourceForTeam }
                    : defaultForScene
                return {
                    ...applyTestAccountFilter(base, currentTeam, filterTestAccountsDefault),
                    showPropertyFilter: true,
                }
            },
        ],
        query: [
            (s) => [s.savedQuery, s.defaultQuery],
            (savedQuery: Node | null, defaultQuery: DataTableNode) => savedQuery || defaultQuery,
        ],
        eventsQuerySource: [
            (s) => [s.query],
            (query: DataTableNode | Node): EventsQuery | null => {
                const source = query && 'source' in query ? query.source : null
                return isEventsQuery(source) ? source : null
            },
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: Scene.ExploreEvents,
                    name: sceneConfigurations[Scene.ExploreEvents].name,
                    iconType: sceneConfigurations[Scene.ExploreEvents].iconType || 'default_icon_type',
                },
            ],
        ],
    }),
    trackedActionToUrl(({ values }) => ({
        setQuery: () => [
            urls.activity(ActivityTab.ExploreEvents),
            {},
            objectsEqual(values.query, values.defaultQuery) ? {} : { q: values.query },
            { replace: true },
        ],
    })),

    urlToAction(({ actions, values }) => {
        const eventsQueryHandler: UrlToActionPayload[keyof UrlToActionPayload] = (_, __, { q: queryParam }): void => {
            if (!equal(queryParam, values.query)) {
                // nothing in the URL
                if (!queryParam) {
                    // restore from the persisted query if present, else fall back to default
                    const persisted = values.savedQueryFor(undefined, 'events')
                    const target = persisted ?? values.defaultQuery
                    if (!objectsEqual(values.query, target)) {
                        actions.setQuery(target)
                    }
                } else {
                    if (typeof queryParam === 'object') {
                        actions.setQuery(queryParam)
                    } else {
                        lemonToast.error('Invalid query in URL')
                        console.error({ queryParam })
                    }
                }
            }
        }
        return {
            [urls.activity(ActivityTab.ExploreEvents)]: eventsQueryHandler,
        }
    }),
])
