export type eventsSceneLogicType = MakeLogicType<
    eventsSceneLogicValues,
    eventsSceneLogicActions,
    Record<string, any>,
    eventsSceneLogicMeta
>

export const eventsSceneLogic = kea<eventsSceneLogicType>([
    key(() => 'scene'),
    path((key) => ['scenes', 'events', 'eventsSceneLogic', key]),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeam'],
            featureFlagLogic,
            ['featureFlags'],
            filterTestAccountsDefaultsLogic,
            ['filterTestAccountsDefault'],
            tabUiStateLogic,
            ['savedQueryFor'],
        ],
        actions: [tabUiStateLogic, ['setSavedQueryForTab']],
    })),

    actions({
        // The URL holds the query as JSON, which drops keys set to undefined. A date edit writes before: undefined.
        // The scene stores the query in its JSON form, so that the scene's own URL update matches the stored query.
        setQuery: (query: Node) => ({ query: JSON.parse(JSON.stringify(query)) as Node }),
        nameFlagCallLookup: (query: Node) => ({ query }),
    }),
    reducers({ savedQuery: [null as Node | null, { setQuery: (_, { query }) => query }] }),
    listeners(({ actions, values }) => ({
        setQuery: ({ query }) => {
            const isDefault = objectsEqual(query, values.defaultQuery)
            actions.setSavedQueryForTab(undefined, 'events', isDefault ? null : query)
        },
        // A lookup that names no event reads the events table. On flag_evaluations_mode 2 that table holds no flag call.
        // This listener runs the lookup again with the flag call event, which reads flag_evaluations.
        // It names the event when that query finds the row.
        // Only a query in the URL dispatches this listener. An edit in the open scene does not dispatch it.
        // A reload after the user clears the event runs the check again, because the URL then holds the cleared lookup.
        nameFlagCallLookup: async ({ query }, breakpoint) => {
            if (
                values.currentTeam?.flag_evaluations_mode !== FLAG_EVALUATIONS_ONLY_MODE ||
                !isDataTableNode(query) ||
                !isEventsQuery(query.source) ||
                !isUnnamedEventLookup(query.source)
            ) {
                return
            }
            const namedSource: EventsQuery = { ...query.source, event: FEATURE_FLAG_CALLED_EVENT }
            const namedQuery: DataTableNode = { ...query, source: namedSource }
            // performQuery reports a failure. On a failure the lookup keeps reading the events table.
            const response = await performQuery({
                ...namedSource,
                select: ['uuid'],
                // An empty order skips the runner's presorted path, which reads flag_evaluations two times.
                orderBy: [],
                limit: 1,
                tags: { productKey: ProductKey.FEATURE_FLAGS },
            }).catch(() => null)
            breakpoint()
            if (response?.results.length && objectsEqual(values.query, query)) {
                actions.setQuery(namedQuery)
            }
        },
    })),
    selectors({
        defaultQuery: [
            (s) => [s.currentTeam, s.filterTestAccountsDefault],
            (
                currentTeam: null | import('~/types').TeamPublicType | import('~/types').TeamType,
                filterTestAccountsDefault: boolean
            ): DataTableNode => {
                const defaultSourceForTeam = currentTeam && getDefaultEventsQueryForTeam(currentTeam)
                const defaultForScene = getDefaultEventsSceneQuery()
                const base = defaultSourceForTeam
                    ? { ...defaultForScene, source: defaultSourceForTeam }
                    : defaultForScene
                return {
                    ...applyTestAccountFilter(base, currentTeam, filterTestAccountsDefault),
                    showPropertyFilter: true,
                }
            },
        ],
        query: [
            (s) => [s.savedQuery, s.defaultQuery],
            (savedQuery: Node | null, defaultQuery: DataTableNode) => savedQuery || defaultQuery,
        ],
        flagCallsNote: [
            (s) => [s.currentTeam, s.query],
            (currentTeam: TeamPublicType | TeamType | null, query: DataTableNode | Node): FlagCallsNote | null => {
                if (
                    !readsFlagEvaluationsTable(currentTeam) ||
                    !isDataTableNode(query) ||
                    !isEventsQuery(query.source)
                ) {
                    return null
                }
                if (!listsOnlyFlagCalls(query.source)) {
                    return currentTeam?.flag_evaluations_mode === FLAG_EVALUATIONS_ONLY_MODE
                        ? 'stored-separately'
                        : null
                }
                const { after } = query.source
                // The runner reads a missing start as the last 24 hours. The retention window covers that range.
                return after && reachesPastFlagEvaluationsRetention(after) ? 'retention' : null
            },
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: Scene.ExploreEvents,
                    name: sceneConfigurations[Scene.ExploreEvents].name,
                    iconType: sceneConfigurations[Scene.ExploreEvents].iconType || 'default_icon_type',
                },
            ],
        ],
    }),
    trackedActionToUrl(({ values }) => ({
        setQuery: () => [
            urls.activity(ActivityTab.ExploreEvents),
            {},
            objectsEqual(values.query, values.defaultQuery) ? {} : { q: values.query },
            { replace: true },
        ],
    })),

    urlToAction(({ actions, values }) => {
        const eventsQueryHandler: UrlToActionPayload[keyof UrlToActionPayload] = (_, __, { q: queryParam }): void => {
            if (!equal(queryParam, values.query)) {
                // nothing in the URL
                if (!queryParam) {
                    // restore from the persisted query if present, else fall back to default
                    const persisted = values.savedQueryFor(undefined, 'events')
                    const target = persisted ?? values.defaultQuery
                    if (!objectsEqual(values.query, target)) {
                        actions.setQuery(target)
                    }
                } else {
                    if (typeof queryParam === 'object') {
                        actions.setQuery(queryParam)
                        actions.nameFlagCallLookup(queryParam)
                    } else {
                        lemonToast.error('Invalid query in URL')
                        console.error({ queryParam })
                    }
                }
            }
        }
        return {
            [urls.activity(ActivityTab.ExploreEvents)]: eventsQueryHandler,
        }
    }),
])
