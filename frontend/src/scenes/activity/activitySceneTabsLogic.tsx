export function isActivityTabKey(key: ActivitySceneTabKey): boolean {
    return (Object.values(ActivityTab) as string[]).includes(key)
}

function toLemonTab(tab: ActivitySceneTab): LemonTab<ActivitySceneTabKey> {
    return {
        key: tab.key,
        label: (
            <span className="flex items-center gap-1" data-attr={tab.dataAttr}>
                {tab.iconType && iconForType(tab.iconType)}
                {tab.label}
            </span>
        ),
        tooltipDocLink: tab.tooltipDocLink,
        link: tab.url,
    }
}

export const activitySceneTabsLogic = kea<activitySceneTabsLogicType>([
    path(['scenes', 'activity', 'activitySceneTabsLogic']),
    connect(() => ({
        values: [
            groupsModel,
            ['aggregationLabel', 'groupTypes', 'groupsAccessStatus'],
            featureFlagLogic,
            ['featureFlags'],
            teamLogic,
            ['currentTeam'],
        ],
    })),
    selectors({
        showFlagCallsTab: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): boolean => flagCallsOnlyInFlagEvaluations(currentTeam),
        ],
        groupTabs: [
            (s) => [s.groupTypes, s.groupsAccessStatus, s.aggregationLabel],
            (
                groupTypes: Map<GroupTypeIndex, GroupType>,
                groupsAccessStatus: GroupsAccessStatus,
                aggregationLabel: (groupTypeIndex: number | null | undefined, deferToUserWording?: boolean) => Noun
            ): ActivitySceneTab[] => groupTabs(groupTypes, groupsAccessStatus, aggregationLabel),
        ],
        sceneTabs: [
            (s) => [s.groupTabs, s.featureFlags, s.showFlagCallsTab],
            (
                groupTabs: ActivitySceneTab[],
                featureFlags: FeatureFlagsSet,
                showFlagCallsTab: boolean
            ): ActivitySceneTab[] => {
                const tabs: ActivitySceneTab[] = [
                    {
                        key: ActivityTab.ExploreEvents,
                        label: 'Events',
                        url: urls.activity(ActivityTab.ExploreEvents),
                        iconType: sceneConfigurations[Scene.ExploreEvents].iconType,
                    },
                    {
                        key: ActivityTab.LiveEvents,
                        label: 'Live',
                        url: urls.activity(ActivityTab.LiveEvents),
                        iconType: sceneConfigurations[Scene.LiveEvents].iconType,
                    },
                    {
                        key: ActivityTab.ExploreSessions,
                        label: 'Sessions',
                        url: urls.activity(ActivityTab.ExploreSessions),
                        iconType: sceneConfigurations[Scene.ExploreSessions].iconType,
                    },
                    // Where the events table holds no new flag calls, the other lists can't show them.
                    ...(showFlagCallsTab
                        ? [
                              {
                                  key: ActivityTab.ExploreFlagCalls,
                                  label: 'Flag calls',
                                  url: urls.activity(ActivityTab.ExploreFlagCalls),
                                  iconType: sceneConfigurations[Scene.ExploreFlagCalls].iconType,
                                  // pinned: autocapture dashboards and Playwright select this tab by data-attr
                                  dataAttr: 'activity-flag-calls-tab',
                              },
                          ]
                        : []),
                    {
                        key: 'persons',
                        label: 'Persons',
                        url: urls.persons(),
                        iconType: sceneConfigurations[Scene.Persons].iconType,
                        tooltipDocLink: 'https://posthog.com/docs/data/persons',
                        dataAttr: 'persons-management-persons-tab',
                    },
                    {
                        key: 'cohorts',
                        label: 'Cohorts',
                        url: urls.cohorts(),
                        iconType: sceneConfigurations[Scene.Cohorts].iconType,
                        tooltipDocLink: 'https://posthog.com/docs/data/cohorts',
                        dataAttr: 'persons-management-cohorts-tab',
                    },
                    ...groupTabs,
                ]

                return featureFlags[FEATURE_FLAGS.LIVESTREAM_HOGQL]
                    ? tabs.filter((tab) => tab.key !== ActivityTab.LiveEvents)
                    : tabs
            },
        ],
        activityTabs: [
            (s) => [s.sceneTabs],
            (sceneTabs: ActivitySceneTab[]): ActivitySceneTab[] => sceneTabs.filter((tab) => isActivityTabKey(tab.key)),
        ],
        peopleTabs: [
            (s) => [s.sceneTabs],
            (sceneTabs: ActivitySceneTab[]): ActivitySceneTab[] =>
                sceneTabs.filter((tab) => !isActivityTabKey(tab.key)),
        ],
        tabsForKey: [
            (s) => [s.activityTabs, s.peopleTabs],
            (
                activityTabs: ActivitySceneTab[],
                peopleTabs: ActivitySceneTab[]
            ): ((activeKey: ActivitySceneTabKey) => LemonTab<ActivitySceneTabKey>[]) => {
                const activityLemonTabs = activityTabs.map(toLemonTab)
                const peopleLemonTabs = peopleTabs.map(toLemonTab)
                return (activeKey) => (isActivityTabKey(activeKey) ? activityLemonTabs : peopleLemonTabs)
            },
        ],
    }),
])
