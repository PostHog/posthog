import { MakeLogicType, connect, kea, path, selectors } from 'kea'

import { GroupsAccessStatus } from 'lib/introductions/groupsAccessLogic'
import { LemonTab } from 'lib/lemon-ui/LemonTabs'
import { capitalizeFirstLetter } from 'lib/utils/strings'
import { sceneConfigurations } from 'scenes/scenes'
import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { iconForType } from '~/layout/panel-layout/ProjectTree/defaultTree'
import { groupsModel } from '~/models/groupsModel'
import { FileSystemIconType } from '~/queries/schema/schema-general'
import { ActivityTab } from '~/types'

import type { Noun } from '../../models/groupsModel'
import type { GroupType, GroupTypeIndex } from '../../types'

export type ActivitySceneTabKey = ActivityTab | 'persons' | 'cohorts' | `groups-${number}`

interface ActivitySceneTab {
    key: ActivitySceneTabKey
    label: string
    url: string
    iconType: FileSystemIconType | undefined
    tooltipDocLink?: string
    // pinned: autocapture dashboards and Playwright select these tabs by data-attr
    dataAttr?: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface activitySceneTabsLogicValues {
    aggregationLabel: (groupTypeIndex: number | null | undefined, deferToUserWording?: boolean) => Noun // groupsModel
    groupTypes: Map<GroupTypeIndex, GroupType> // groupsModel
    groupsAccessStatus: GroupsAccessStatus // groupsModel
    groupTabs: ActivitySceneTab[]
    tabs: LemonTab<ActivitySceneTabKey>[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface activitySceneTabsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        groupTabs: (
            groupTypes: Map<GroupTypeIndex, GroupType>,
            groupsAccessStatus: GroupsAccessStatus,
            aggregationLabel: (groupTypeIndex: number | null | undefined, deferToUserWording?: boolean) => Noun
        ) => ActivitySceneTab[]
        tabs: (groupTabs: ActivitySceneTab[]) => LemonTab<ActivitySceneTabKey>[]
    }
}

export type activitySceneTabsLogicType = MakeLogicType<
    activitySceneTabsLogicValues,
    {},
    Record<string, any>,
    activitySceneTabsLogicMeta
>

export const activitySceneTabsLogic = kea<activitySceneTabsLogicType>([
    path(['scenes', 'activity', 'activitySceneTabsLogic']),
    connect(() => ({
        values: [groupsModel, ['aggregationLabel', 'groupTypes', 'groupsAccessStatus']],
    })),
    selectors({
        groupTabs: [
            (s) => [s.groupTypes, s.groupsAccessStatus, s.aggregationLabel],
            (
                groupTypes: Map<GroupTypeIndex, GroupType>,
                groupsAccessStatus: GroupsAccessStatus,
                aggregationLabel: (groupTypeIndex: number | null | undefined, deferToUserWording?: boolean) => Noun
            ): ActivitySceneTab[] => {
                const showGroupsIntroductionPage = [
                    GroupsAccessStatus.HasAccess,
                    GroupsAccessStatus.HasGroupTypes,
                    GroupsAccessStatus.NoAccess,
                ].includes(groupsAccessStatus)

                if (showGroupsIntroductionPage) {
                    return [
                        {
                            key: 'groups-0',
                            label: 'Groups',
                            url: urls.groups(0),
                            iconType: 'group',
                            dataAttr: 'persons-management-groups-0-tab',
                        },
                    ]
                }

                return Array.from(groupTypes.values()).map(({ group_type_index }) => ({
                    key: `groups-${group_type_index}`,
                    label: capitalizeFirstLetter(aggregationLabel(group_type_index).plural),
                    url: urls.groups(group_type_index),
                    iconType: `group_${group_type_index}` as FileSystemIconType,
                    dataAttr: `persons-management-groups-${group_type_index}-tab`,
                }))
            },
        ],
        tabs: [
            (s) => [s.groupTabs],
            (groupTabs: ActivitySceneTab[]): LemonTab<ActivitySceneTabKey>[] => {
                const tabs: ActivitySceneTab[] = [
                    {
                        key: ActivityTab.ExploreEvents,
                        label: 'Events',
                        url: urls.activity(ActivityTab.ExploreEvents),
                        iconType: sceneConfigurations[Scene.ExploreEvents].iconType,
                    },
                    {
                        key: ActivityTab.LiveEvents,
                        label: 'Live',
                        url: urls.activity(ActivityTab.LiveEvents),
                        iconType: sceneConfigurations[Scene.LiveEvents].iconType,
                    },
                    {
                        key: ActivityTab.ExploreSessions,
                        label: 'Sessions',
                        url: urls.activity(ActivityTab.ExploreSessions),
                        iconType: sceneConfigurations[Scene.ExploreSessions].iconType,
                    },
                    {
                        key: 'persons',
                        label: 'Persons',
                        url: urls.persons(),
                        iconType: sceneConfigurations[Scene.Persons].iconType,
                        tooltipDocLink: 'https://posthog.com/docs/data/persons',
                        dataAttr: 'persons-management-persons-tab',
                    },
                    {
                        key: 'cohorts',
                        label: 'Cohorts',
                        url: urls.cohorts(),
                        iconType: sceneConfigurations[Scene.Cohorts].iconType,
                        tooltipDocLink: 'https://posthog.com/docs/data/cohorts',
                        dataAttr: 'persons-management-cohorts-tab',
                    },
                    ...groupTabs,
                ]

                return tabs.map((tab) => ({
                    key: tab.key,
                    label: (
                        <span className="flex items-center gap-1" data-attr={tab.dataAttr}>
                            {tab.iconType && iconForType(tab.iconType)}
                            {tab.label}
                        </span>
                    ),
                    tooltipDocLink: tab.tooltipDocLink,
                    link: tab.url,
                }))
            },
        ],
    }),
])
