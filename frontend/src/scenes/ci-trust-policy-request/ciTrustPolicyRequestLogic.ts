async function resolveRequest(
    resolve: () => Promise<CITrustPolicyRequestApi>,
    event: string,
    successMessage: string,
    failureMessage: string
): Promise<CITrustPolicyRequestApi> {
    try {
        const resolved = await resolve()
        posthog.capture(event)
        lemonToast.success(successMessage)
        return resolved
    } catch (error) {
        lemonToast.error(readableErrorMessage(error) ?? failureMessage)
        throw error
    }
}

