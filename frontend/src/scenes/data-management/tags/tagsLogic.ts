export type tagsLogicType = MakeLogicType<tagsLogicValues, tagsLogicActions, Record<string, any>, tagsLogicMeta>

export const tagsLogic = kea<tagsLogicType>([
    path(['scenes', 'data-management', 'tags', 'tagsLogic']),
    connect(() => ({
        values: [
            tagManagementAccessLogic,
            ['canManageTags'],
            projectLogic,
            ['currentProjectId'],
            teamLogic,
            ['currentTeamId'],
        ],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setPage: (page: number) => ({ page }),
        setOrdering: (ordering: TagOrdering) => ({ ordering }),
        openRename: (tag: TagDefinitionApi) => ({ tag }),
        setRenameName: (name: string) => ({ name }),
        openMerge: (tag: TagDefinitionApi) => ({ tag }),
        setTarget: (tag: TagDefinitionApi | null) => ({ tag }),
        setDestinationSearch: (search: string) => ({ search }),
        loadMoreDestinations: true,
        retryDestinations: true,
        openDelete: (tag: TagDefinitionApi) => ({ tag }),
        closeModals: true,
        submitRename: true,
        submitMerge: true,
        submitDelete: true,
        finishMutation: (operation: TagMutation) => ({ operation }),
        failMutation: (operation: TagMutation, error: unknown) => ({ operation, error }),
        reportUncertainMutation: (result: UncertainTagMutation) => result,
    }),
    loaders(({ actions, values, cache }) => {
        function isCurrentEnvironment(projectId: number, environmentId: number): boolean {
            return values.currentProjectId === projectId && values.currentTeamId === environmentId
        }

        async function reconcileMutation(
            operation: TagMutation,
            projectId: number,
            environmentId: number,
            tagId: string,
            expectedName?: string
        ): Promise<TagMutation | null> {
            let tag: TagDefinitionApi | null = null
            let message = 'Could not confirm this change. Refresh the list before trying again.'
            try {
                tag = await api.tagDefinitionsRetrieve(String(projectId), tagId, getTagRequestOptions(environmentId))
                message = 'Could not confirm this change. Review the current tag before trying again.'
            } catch (error) {
                if (error instanceof ApiError && error.status === 404) {
                    message = 'This tag is no longer available. Check the refreshed list.'
                }
            }
            if (!isCurrentEnvironment(projectId, environmentId)) {
                return null
            }
            if (operation === 'rename' && tag?.name === expectedName) {
                return operation
            }
            actions.reportUncertainMutation({ operation, tag, message })
            return null
        }

        async function saveMutation(
            operation: TagMutation,
            tagId: string,
            save: (projectId: string, options: RequestInit) => Promise<unknown>,
            expectedName?: string
        ): Promise<TagMutation | null> {
            const projectId = values.currentProjectId
            const environmentId = values.currentTeamId
            if (!values.canManageTags || projectId === null || environmentId === null) {
                return null
            }
            try {
                await save(String(projectId), getTagRequestOptions(environmentId))
                return isCurrentEnvironment(projectId, environmentId) ? operation : null
            } catch (error) {
                if (!isCurrentEnvironment(projectId, environmentId)) {
                    return null
                }
                if (isDefinitiveTagMutationError(error)) {
                    throw error
                }
            }
            return await reconcileMutation(operation, projectId, environmentId, tagId, expectedName)
        }

        return {
            tagPage: [
                null as PaginatedTagDefinitionListApi | null,
                {
                    loadTagDefinitions: async (_: void, breakpoint) => {
                        const projectId = values.currentProjectId
                        const environmentId = values.currentTeamId
                        if (!values.canManageTags || projectId === null || environmentId === null) {
                            return null
                        }
                        if (!cache.openedReported) {
                            posthog.capture('tag management opened')
                            cache.openedReported = true
                        }
                        const page = await api
                            .tagDefinitionsList(
                                String(projectId),
                                {
                                    search: values.search,
                                    ordering: values.ordering,
                                    offset: (values.page - 1) * TAG_PAGE_SIZE,
                                    limit: TAG_PAGE_SIZE,
                                },
                                getTagRequestOptions(environmentId)
                            )
                            .catch((error) => {
                                breakpoint()
                                throw error
                            })
                        breakpoint()
                        return values.canManageTags &&
                            values.currentProjectId === projectId &&
                            values.currentTeamId === environmentId
                            ? page
                            : null
                    },
                },
            ],
            destinationPage: [
                null as PaginatedTagDefinitionListApi | null,
                {
                    loadTagDestinations: async ({ append }: { append?: boolean }, breakpoint) => {
                        const projectId = values.currentProjectId
                        const environmentId = values.currentTeamId
                        if (
                            !values.canManageTags ||
                            projectId === null ||
                            environmentId === null ||
                            !values.tagToMerge
                        ) {
                            return null
                        }
                        const sourceId = values.tagToMerge.id
                        const previous = append ? (values.destinationPage?.results ?? []) : []
                        await breakpoint(150)
                        const page = await api
                            .tagDefinitionsList(
                                String(projectId),
                                {
                                    search: values.destinationSearch,
                                    ordering: 'name',
                                    offset: previous.length,
                                    limit: TAG_PAGE_SIZE,
                                },
                                getTagRequestOptions(environmentId)
                            )
                            .catch((error) => {
                                breakpoint()
                                throw error
                            })
                        breakpoint()
                        return values.currentProjectId === projectId &&
                            values.currentTeamId === environmentId &&
                            values.tagToMerge?.id === sourceId
                            ? { ...page, results: [...previous, ...page.results] }
                            : null
                    },
                },
            ],
            preview: [
                null as TagMergePreviewApi | null,
                {
                    clearTagMergePreview: () => null,
                    loadTagMergePreview: async (
                        { sourceId, targetId }: { sourceId: string | null; targetId: string | null },
                        breakpoint
                    ) => {
                        const projectId = values.currentProjectId
                        const environmentId = values.currentTeamId
                        if (
                            !values.canManageTags ||
                            projectId === null ||
                            environmentId === null ||
                            !sourceId ||
                            !targetId
                        ) {
                            return null
                        }
                        const preview = await api
                            .tagDefinitionsMergePreviewRetrieve(
                                String(projectId),
                                sourceId,
                                { target_id: targetId },
                                getTagRequestOptions(environmentId)
                            )
                            .catch((error) => {
                                breakpoint()
                                throw error
                            })
                        breakpoint()
                        return values.currentProjectId === projectId &&
                            values.currentTeamId === environmentId &&
                            values.tagToMerge?.id === sourceId &&
                            values.target?.id === targetId
                            ? preview
                            : null
                    },
                },
            ],
            mutation: [
                null as TagMutation | null,
                {
                    renameManagedTag: ({ tag, name }: { tag: TagDefinitionApi; name: string }) =>
                        saveMutation(
                            'rename',
                            tag.id,
                            (projectId, options) =>
                                api.tagDefinitionsPartialUpdate(projectId, tag.id, { name }, options),
                            name.trim().toLowerCase()
                        ),
                    mergeManagedTag: ({ sourceId, targetId }: { sourceId: string; targetId: string }) =>
                        saveMutation('merge', sourceId, (projectId, options) =>
                            api.tagDefinitionsMergeCreate(projectId, sourceId, { target_id: targetId }, options)
                        ),
                    deleteManagedTag: ({ tag }: { tag: TagDefinitionApi }) =>
                        saveMutation('delete', tag.id, (projectId, options) =>
                            api.tagDefinitionsDestroy(projectId, tag.id, options)
                        ),
                },
            ],
        }
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        page: [1, { setPage: (_, { page }) => page, setSearch: () => 1, setOrdering: () => 1 }],
        ordering: ['name' as TagOrdering, { setOrdering: (_, { ordering }) => ordering }],
        tagToRename: [
            null as TagDefinitionApi | null,
            {
                openRename: (_, { tag }) => tag,
                closeModals: () => null,
                reportUncertainMutation: (previous, { operation, tag }) => (operation === 'rename' ? tag : previous),
            },
        ],
        renameName: ['', { openRename: (_, { tag }) => tag.name, setRenameName: (_, { name }) => name }],
        tagToMerge: [
            null as TagDefinitionApi | null,
            {
                openMerge: (_, { tag }) => tag,
                closeModals: () => null,
                reportUncertainMutation: (previous, { operation, tag }) => (operation === 'merge' ? tag : previous),
            },
        ],
        target: [
            null as TagDefinitionApi | null,
            { openMerge: () => null, setTarget: (_, { tag }) => tag, closeModals: () => null },
        ],
        destinationSearch: ['', { openMerge: () => '', setDestinationSearch: (_, { search }) => search }],
        destinationAppend: [false, { loadTagDestinations: (_, { append }) => !!append }],
        tagToDelete: [
            null as TagDefinitionApi | null,
            {
                openDelete: (_, { tag }) => tag,
                closeModals: () => null,
                reportUncertainMutation: (previous, { operation, tag }) => (operation === 'delete' ? tag : previous),
            },
        ],
        listError: [
            null as string | null,
            { loadTagDefinitions: () => null, loadTagDefinitionsFailure: () => 'Could not load tags. Try again.' },
        ],
        destinationError: [
            null as string | null,
            {
                loadTagDestinations: () => null,
                loadTagDestinationsFailure: () => 'Could not load destination tags. Try again.',
            },
        ],
        previewError: [
            null as string | null,
            {
                loadTagMergePreview: () => null,
                loadTagMergePreviewFailure: () =>
                    'Could not preview this merge. Choose an existing destination and try again.',
            },
        ],
        mutationError: [
            null as string | null,
            {
                openRename: () => null,
                openMerge: () => null,
                openDelete: () => null,
                finishMutation: () => null,
                failMutation: (_, { error }) => getTagError(error),
                reportUncertainMutation: (_, { message }) => message,
            },
        ],
    }),
    selectors({
        destinations: [
            (s) => [s.destinationPage, s.tagToMerge],
            (page: tagsLogicValues['destinationPage'], source: tagsLogicValues['tagToMerge']): TagDefinitionApi[] =>
                (page?.results ?? []).filter((tag: TagDefinitionApi) => tag.id !== source?.id),
        ],
        canSubmitMerge: [
            (s) => [
                s.canManageTags,
                s.currentProjectId,
                s.tagToMerge,
                s.target,
                s.preview,
                s.previewLoading,
                s.mutationLoading,
            ],
            (
                allowed: tagsLogicValues['canManageTags'],
                currentProjectId: tagsLogicValues['currentProjectId'],
                source: tagsLogicValues['tagToMerge'],
                target: tagsLogicValues['target'],
                preview: tagsLogicValues['preview'],
                loading: tagsLogicValues['previewLoading'],
                saving: tagsLogicValues['mutationLoading']
            ): boolean =>
                allowed &&
                currentProjectId !== null &&
                !loading &&
                !saving &&
                !!source &&
                !!target &&
                preview?.tag.id === target.id,
        ],
    }),
    listeners(({ actions, values }) => ({
        setSearch: async (_, breakpoint) => {
            await breakpoint(200)
            actions.loadTagDefinitions()
        },
        setPage: () => actions.loadTagDefinitions(),
        setOrdering: () => actions.loadTagDefinitions(),
        openMerge: () => {
            actions.clearTagMergePreview()
            actions.loadTagDestinations({})
        },
        setTarget: ({ tag }) => {
            actions.clearTagMergePreview()
            actions.loadTagMergePreview({ sourceId: values.tagToMerge?.id ?? null, targetId: tag?.id ?? null })
        },
        setDestinationSearch: () => actions.loadTagDestinations({}),
        loadMoreDestinations: () => {
            if (!values.destinationPageLoading && !values.destinationError && values.destinationPage?.next) {
                actions.loadTagDestinations({ append: true })
            }
        },
        retryDestinations: () => actions.loadTagDestinations({ append: values.destinationAppend }),
        submitRename: () => {
            if (
                values.canManageTags &&
                values.currentProjectId !== null &&
                values.tagToRename &&
                values.renameName.trim() &&
                !values.mutationLoading
            ) {
                posthog.capture('tag management action started', { action: 'rename' })
                actions.renameManagedTag({ tag: values.tagToRename, name: values.renameName })
            }
        },
        submitMerge: () => {
            if (values.canSubmitMerge && values.tagToMerge && values.target) {
                posthog.capture('tag management action started', { action: 'merge' })
                actions.mergeManagedTag({ sourceId: values.tagToMerge.id, targetId: values.target.id })
            }
        },
        submitDelete: () => {
            if (
                values.canManageTags &&
                values.currentProjectId !== null &&
                values.tagToDelete?.usage_count === 0 &&
                !values.mutationLoading
            ) {
                posthog.capture('tag management action started', { action: 'delete' })
                actions.deleteManagedTag({ tag: values.tagToDelete })
            }
        },
        renameManagedTagSuccess: ({ mutation }) => {
            if (mutation) {
                actions.finishMutation(mutation)
            }
        },
        mergeManagedTagSuccess: ({ mutation }) => {
            if (mutation) {
                actions.finishMutation(mutation)
            }
        },
        deleteManagedTagSuccess: ({ mutation }) => {
            if (mutation) {
                actions.finishMutation(mutation)
            }
        },
        renameManagedTagFailure: ({ errorObject }) => actions.failMutation('rename', errorObject),
        mergeManagedTagFailure: ({ errorObject }) => actions.failMutation('merge', errorObject),
        deleteManagedTagFailure: ({ errorObject }) => actions.failMutation('delete', errorObject),
        finishMutation: ({ operation }) => {
            posthog.capture('tag management action completed', { action: operation })
            actions.closeModals()
            actions.loadTagDefinitions()
        },
        failMutation: ({ operation }) => {
            posthog.capture('tag management action failed', { action: operation })
            if (operation === 'merge') {
                actions.setTarget(null)
                actions.loadTagDestinations({})
            } else if (operation === 'delete') {
                actions.loadTagDefinitions()
            }
        },
        reportUncertainMutation: ({ operation, tag, message }) => {
            posthog.capture('tag management action outcome unknown', { action: operation })
            actions.loadTagDefinitions()
            if (tag === null) {
                actions.closeModals()
                lemonToast.warning(message)
            } else if (operation === 'merge') {
                actions.setTarget(null)
                actions.loadTagDestinations({})
            }
        },
        [projectLogic.actionTypes.loadCurrentProjectSuccess]: () => actions.loadTagDefinitions(),
        [teamLogic.actionTypes.loadCurrentTeamSuccess]: () => actions.loadTagDefinitions(),
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
            if (!values.tagPageLoading) {
                actions.loadTagDefinitions()
            }
        },
        [organizationLogic.actionTypes.loadCurrentOrganizationSuccess]: () => {
            if (!values.tagPageLoading) {
                actions.loadTagDefinitions()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.canManageTags) {
            actions.loadTagDefinitions()
        }
    }),
])
