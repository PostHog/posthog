export type TagOrdering = 'name' | '-name' | 'usage_count' | '-usage_count'
type TagMutation = 'rename' | 'merge' | 'delete'
type UncertainTagMutation = { operation: TagMutation; tag: TagDefinitionApi | null; message: string }
export const TAG_PAGE_SIZE = 100
export const TAG_REFERENCE_WARNING =
    'Saved filters, URLs, and custom queries that use the old name will need separate updates.'

function getTagRequestOptions(environmentId: number): RequestInit {
    return { headers: { 'X-PostHog-Environment-Id': String(environmentId) } }
}

function getTagError(error: unknown): string {
    if (error && typeof error === 'object' && 'detail' in error && typeof error.detail === 'string') {
        return error.detail
    }
    if (error instanceof Error && error.message) {
        return error.message
    }
    return 'Could not save this change. Refresh the list and try again.'
}

function isDefinitiveTagMutationError(error: unknown): boolean {
    return (
        error instanceof ApiError && !!error.status && error.status >= 400 && error.status < 500 && error.status !== 408
    )
}

