import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { Sorting } from 'lib/lemon-ui/LemonTable'
import { teamLogic } from 'scenes/teamLogic'

import { insightsList } from 'products/product_analytics/frontend/generated/api'
import type {
    InsightApi,
    InsightsListParams,
    PaginatedInsightListApi,
} from 'products/product_analytics/frontend/generated/api.schemas'

export type DefinitionInsightsType = 'event' | 'property'

export interface DefinitionInsightsLogicProps {
    definitionType: DefinitionInsightsType
    name: string
}

export interface DefinitionInsightsSummary {
    insightCount: number
    dashboardCount: number
    /** True when the project has more matching insights than one summary request returns. */
    dashboardCountIsPartial: boolean
}

export const DEFINITION_INSIGHTS_PER_PAGE = 10
const SUMMARY_LIMIT = 100
const DEFAULT_ORDER = '-last_modified_at'

// The insights list filters on `events` and `properties`, but its OpenAPI schema does not declare
// either, so the generated params type lacks both.
type DefinitionInsightsListParams = InsightsListParams & { events?: string; properties?: string }

function listParams(props: DefinitionInsightsLogicProps): DefinitionInsightsListParams {
    const names = JSON.stringify([props.name])
    return {
        saved: true,
        basic: true,
        ...(props.definitionType === 'event' ? { events: names } : { properties: names }),
    }
}

export function dashboardIdsOf(insight: InsightApi): number[] {
    return insight.dashboard_tiles.filter((tile) => !tile.deleted).map((tile) => tile.dashboard_id)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface definitionInsightsLogicValues {
    currentProjectId: number | string // teamLogic
    insights: PaginatedInsightListApi | null
    insightsFailed: boolean
    insightsLoading: boolean
    order: string
    page: number
    search: string
    sorting: Sorting | null
    summary: DefinitionInsightsSummary | null
    summaryFailed: boolean
    summaryLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface definitionInsightsLogicActions {
    loadInsights: (_: void) => void
    loadInsightsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadInsightsSuccess: (
        insights: PaginatedInsightListApi | null,
        payload?: void
    ) => {
        insights: PaginatedInsightListApi | null
        payload?: void
    }
    loadSummary: () => any
    loadSummaryFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSummarySuccess: (
        summary: DefinitionInsightsSummary | null,
        payload?: any
    ) => {
        summary: DefinitionInsightsSummary | null
        payload?: any
    }
    reportInsightOpened: () => {
        value: true
    }
    setOrder: (order: string | null) => {
        order: string | null
    }
    setPage: (page: number) => {
        page: number
    }
    setSearch: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface definitionInsightsLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        sorting: (order: string) => Sorting | null
    }
}

export type definitionInsightsLogicType = MakeLogicType<
    definitionInsightsLogicValues,
    definitionInsightsLogicActions,
    DefinitionInsightsLogicProps,
    definitionInsightsLogicMeta
>

export const definitionInsightsLogic = kea<definitionInsightsLogicType>([
    path((key) => ['scenes', 'data-management', 'definition', 'usage', 'definitionInsightsLogic', key]),
    props({} as DefinitionInsightsLogicProps),
    key(({ definitionType, name }) => `${definitionType}/${name}`),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setOrder: (order: string | null) => ({ order }),
        setPage: (page: number) => ({ page }),
        reportInsightOpened: true,
    }),
    loaders(({ values, props }) => ({
        insights: [
            null as PaginatedInsightListApi | null,
            {
                loadInsights: async (_: void, breakpoint): Promise<PaginatedInsightListApi | null> => {
                    const response = await insightsList(String(values.currentProjectId), {
                        ...listParams(props),
                        order: values.order,
                        search: values.search || undefined,
                        limit: DEFINITION_INSIGHTS_PER_PAGE,
                        offset: (values.page - 1) * DEFINITION_INSIGHTS_PER_PAGE,
                    })
                    // Drops a response that a newer search, sort or page request has superseded.
                    breakpoint()
                    return response
                },
            },
        ],
        summary: [
            null as DefinitionInsightsSummary | null,
            {
                loadSummary: async (): Promise<DefinitionInsightsSummary | null> => {
                    const response = await insightsList(String(values.currentProjectId), {
                        ...listParams(props),
                        limit: SUMMARY_LIMIT,
                    })
                    return {
                        insightCount: response.count,
                        dashboardCount: new Set(response.results.flatMap(dashboardIdsOf)).size,
                        dashboardCountIsPartial: response.count > response.results.length,
                    }
                },
            },
        ],
    })),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        order: [DEFAULT_ORDER as string, { setOrder: (_, { order }) => order || DEFAULT_ORDER }],
        page: [
            1,
            {
                setPage: (_, { page }) => page,
                setSearch: () => 1,
                setOrder: () => 1,
            },
        ],
        insightsFailed: [
            false,
            {
                loadInsights: () => false,
                loadInsightsSuccess: () => false,
                loadInsightsFailure: () => true,
            },
        ],
        summaryFailed: [
            false,
            {
                loadSummary: () => false,
                loadSummarySuccess: () => false,
                loadSummaryFailure: () => true,
            },
        ],
    }),
    selectors({
        sorting: [
            (s) => [s.order],
            (order: string): Sorting | null =>
                order.startsWith('-') ? { columnKey: order.slice(1), order: -1 } : { columnKey: order, order: 1 },
        ],
    }),
    listeners(({ actions, props }) => ({
        setPage: () => actions.loadInsights(),
        setOrder: () => actions.loadInsights(),
        setSearch: async (_, breakpoint) => {
            await breakpoint(300)
            actions.loadInsights()
        },
        reportInsightOpened: () => {
            // pinned: analytics event name, renaming it breaks dashboards built on it
            posthog.capture('definition usage insight opened', { definition_type: props.definitionType })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadInsights()
        actions.loadSummary()
    }),
])
