export const databaseTableListLogic = kea<databaseTableListLogicType>([
    path(['scenes', 'data-management', 'database', 'databaseTableListLogic']),
    actions({
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        setConnection: (connectionId: string | null) => ({ connectionId }),
        refreshDatabaseSchema: true,
        // Drop any direct-connection scope and go back to the project's own catalog. This logic is
        // shared and outlives the SQL editor, so without an explicit reset every other consumer
        // (sources list, taxonomic filters, joins) keeps seeing the connection's tables.
        resetConnectionScope: true,
        hydrateTableFields: (tableNames: string[]) => ({ tableNames }),
        hydrateTableFieldsStart: (tableNames: string[]) => ({ tableNames }),
        hydrateTableFieldsSuccess: (tableNames: string[], tables: Record<string, DatabaseSchemaTable>) => ({
            tableNames,
            tables,
        }),
        hydrateTableFieldsFailure: (tableNames: string[]) => ({ tableNames }),
        setDatabaseFieldsComplete: (complete: boolean) => ({ complete }),
        // Upgrade a shallow (table names only) schema to a full one. Consumers that read
        // `fields` across many tables at once (search, join modal, expressions) call this.
        ensureAllTableFields: true,
    }),
    loaders(({ values, actions }) => ({
        database: [
            null as Required<DatabaseSchemaQueryResponse> | null,
            {
                loadDatabase: async ({
                    force,
                    shallow,
                }: {
                    force?: boolean
                    shallow?: boolean
                } = {}): Promise<Required<DatabaseSchemaQueryResponse> | null> => {
                    const requestConnectionId = values.connectionId ?? undefined
                    const requestKey = requestConnectionId ?? '__posthog__'

                    // Non-forced loads may piggyback on an identical in-flight request and adopt its
                    // epoch (they don't start a new generation). A forced refresh always issues a
                    // fresh request so it can never return pre-mutation data (and never waits on a
                    // hung stale request). A full load never piggybacks on a shallow request — it
                    // would come back without any fields.
                    if (
                        !force &&
                        inFlightDatabaseLoadKey === requestKey &&
                        inFlightDatabaseLoadPromise &&
                        (shallow || !inFlightDatabaseLoadIsShallow)
                    ) {
                        const epoch = inFlightDatabaseLoadEpoch
                        const result = await inFlightDatabaseLoadPromise
                        // Reading `values` post-unmount throws kea's path-not-found error.
                        if (!databaseTableListLogic.isMounted()) {
                            return null
                        }
                        if (epoch !== latestDatabaseLoadEpoch) {
                            return values.database
                        }
                        return result
                    }

                    const epoch = ++latestDatabaseLoadEpoch
                    const request = performQuery(
                        setLatestVersionsOnQuery({
                            kind: NodeKind.DatabaseSchemaQuery,
                            connectionId: requestConnectionId,
                            includeFields: shallow ? false : undefined,
                        }) as DatabaseSchemaQuery
                    )

                    inFlightDatabaseLoadKey = requestKey
                    inFlightDatabaseLoadPromise = request
                    inFlightDatabaseLoadEpoch = epoch
                    inFlightDatabaseLoadIsShallow = !!shallow

                    let database: Required<DatabaseSchemaQueryResponse> | null = null
                    try {
                        database = await request
                    } finally {
                        // Identity check, not key equality: a concurrent forced refresh may have
                        // replaced the in-flight slot with its own request under the same key.
                        if (inFlightDatabaseLoadPromise === request) {
                            inFlightDatabaseLoadKey = null
                            inFlightDatabaseLoadPromise = null
                        }
                    }

                    // Reading `values` post-unmount throws kea's path-not-found error.
                    if (!databaseTableListLogic.isMounted()) {
                        return null
                    }

                    // A newer load or refresh started after us: discard this possibly-stale response
                    // rather than clobbering the fresher schema.
                    if (epoch !== latestDatabaseLoadEpoch) {
                        return values.database
                    }

                    const currentConnectionId = values.connectionId ?? undefined
                    if (currentConnectionId !== requestConnectionId) {
                        return values.database
                    }

                    actions.setDatabaseFieldsComplete(!shallow)
                    return database
                },
            },
        ],
    })),
    reducers({
        searchTerm: ['', { setSearchTerm: (_, { searchTerm }) => searchTerm }],
        database: {
            hydrateTableFieldsSuccess: (state, { tableNames, tables }) => {
                if (!state) {
                    return state
                }
                const nextTables = { ...state.tables, ...tables }
                for (const tableName of tableNames) {
                    if (!(tableName in tables)) {
                        delete nextTables[tableName]
                    }
                }
                return { ...state, tables: nextTables }
            },
        },
        // False while the store only holds a shallow schema (table names and metadata, no fields).
        databaseFieldsComplete: [
            true,
            {
                setDatabaseFieldsComplete: (_, { complete }) => complete,
            },
        ],
        tableFieldsStatus: [
            {} as TableFieldsStatus,
            {
                hydrateTableFieldsStart: (state, { tableNames }) => {
                    const next = { ...state }
                    for (const name of tableNames) {
                        next[name] = 'loading'
                    }
                    return next
                },
                hydrateTableFieldsSuccess: (state, { tableNames, tables }) => {
                    const next = { ...state }
                    for (const name of tableNames) {
                        next[name] = name in tables ? 'loaded' : 'missing'
                    }
                    return next
                },
                hydrateTableFieldsFailure: (state, { tableNames }) => {
                    const next = { ...state }
                    for (const name of tableNames) {
                        next[name] = 'error'
                    }
                    return next
                },
                // Any full or shallow reload replaces `database.tables` wholesale, so per-table
                // hydration state no longer describes the store.
                loadDatabaseSuccess: () => ({}),
                loadDatabaseFailure: () => ({}),
                setConnection: () => ({}),
                resetConnectionScope: () => ({}),
            },
        ],
        // Without this the logic settles on `database: null, databaseLoading: false` after a failed
        // load, which every consumer reads as "loaded, and the project has no tables".
        databaseLoadError: [
            null as string | null,
            {
                loadDatabase: () => null,
                loadDatabaseSuccess: () => null,
                loadDatabaseFailure: (_, { error }) => error || 'Unknown error',
            },
        ],
        connectionId: [
            null as string | null,
            { setConnection: (_, { connectionId }) => connectionId, resetConnectionScope: () => null },
        ],
    }),
    selectors({
        allPosthogTables: [
            (s) => [s.allTables],
            (allTables: DatabaseSchemaTable[]): DatabaseSchemaTable[] => {
                return allTables.filter((n) => n.type === 'posthog')
            },
            { resultEqualityCheck: objectsEqual },
        ],
        filteredTables: [
            (s) => [s.allTables, s.searchTerm],
            (allTables: DatabaseSchemaTable[], searchTerm: string): DatabaseSchemaTable[] => {
                return allTables
                    .filter(({ name }) => name.toLowerCase().includes(searchTerm.toLowerCase()))
                    .sort((a, b) => a.name.localeCompare(b.name))
            },
            { resultEqualityCheck: objectsEqual },
        ],
        allTables: [
            (s) => [s.database, s.databaseLoading],
            (
                database: Required<DatabaseSchemaQueryResponse> | null,
                databaseLoading: boolean
            ): DatabaseSchemaTable[] => {
                if (databaseLoading || !database || !database.tables) {
                    return []
                }

                return Object.values(database.tables)
            },
            { resultEqualityCheck: objectsEqual },
        ],
        allTablesMap: [
            (s) => [s.allTables],
            (allTables: DatabaseSchemaTable[]): Record<string, DatabaseSchemaTable> =>
                toMapByName(allTables.filter((t) => t.type !== 'endpoint')),
            { resultEqualityCheck: objectsEqual },
        ],
        posthogTables: [
            (s) => [s.allPosthogTables, s.connectionId],
            (allPosthogTables: DatabaseSchemaTable[], connectionId: string | null): DatabaseSchemaTable[] => {
                if (connectionId) {
                    return []
                }
                const visiblePosthogTableNames = new Set(['events', 'groups', 'persons', 'sessions'])
                return allPosthogTables.filter((table) => visiblePosthogTableNames.has(table.name))
            },
            { resultEqualityCheck: objectsEqual },
        ],
        posthogTablesMap: [
            (s) => [s.posthogTables],
            (posthogTables: DatabaseSchemaTable[]): Record<string, DatabaseSchemaTable> => toMapByName(posthogTables),
            { resultEqualityCheck: objectsEqual },
        ],
        systemTables: [
            (s) => [s.allTables, s.connectionId],
            (allTables: DatabaseSchemaTable[], connectionId: string | null): DatabaseSchemaTable[] => {
                if (connectionId) {
                    return []
                }
                return allTables.filter((n) => n.type === 'system')
            },
            { resultEqualityCheck: objectsEqual },
        ],
        systemTablesMap: [
            (s) => [s.systemTables],
            (systemTables: DatabaseSchemaTable[]): Record<string, DatabaseSchemaTable> => toMapByName(systemTables),
            { resultEqualityCheck: objectsEqual },
        ],
        dataWarehouseTables: [
            (s) => [s.allTables],
            (allTables: DatabaseSchemaTable[]): DatabaseSchemaDataWarehouseTable[] => {
                return allTables.filter((n): n is DatabaseSchemaDataWarehouseTable => n.type === 'data_warehouse')
            },
            { resultEqualityCheck: objectsEqual },
        ],
        // Tables synced from an external data source (Stripe, Postgres, etc). Excludes views/saved
        // queries and self-managed S3 tables — only these can trigger CDP from a warehouse sync.
        externalDataSourceTables: [
            (s) => [s.dataWarehouseTables],
            (dataWarehouseTables: DatabaseSchemaDataWarehouseTable[]): DatabaseSchemaDataWarehouseTable[] => {
                return dataWarehouseTables.filter((table) => table.source != null)
            },
            { resultEqualityCheck: objectsEqual },
        ],
        dataWarehouseTablesMap: [
            (s) => [s.dataWarehouseTables, s.views],
            (
                dataWarehouseTables: DatabaseSchemaDataWarehouseTable[],
                views: DatabaseSchemaViewTable[]
            ): Record<string, DatabaseSchemaDataWarehouseTable | DatabaseSchemaViewTable> =>
                toMapByName([...dataWarehouseTables, ...views]),
            { resultEqualityCheck: objectsEqual },
        ],
        dataWarehouseTablesMapById: [
            (s) => [s.dataWarehouseTables, s.views],
            (
                dataWarehouseTables: DatabaseSchemaDataWarehouseTable[],
                views: DatabaseSchemaViewTable[]
            ): Record<string, DatabaseSchemaDataWarehouseTable | DatabaseSchemaViewTable> =>
                toMapById([...dataWarehouseTables, ...views]),
            { resultEqualityCheck: objectsEqual },
        ],
        views: [
            (s) => [s.allTables],
            (allTables: DatabaseSchemaTable[]): DatabaseSchemaViewTable[] => {
                return allTables.filter((n): n is DatabaseSchemaViewTable => n.type === 'view')
            },
            { resultEqualityCheck: objectsEqual },
        ],
        managedViews: [
            (s) => [s.allTables],
            (allTables: DatabaseSchemaTable[]): DatabaseSchemaManagedViewTable[] => {
                return allTables.filter((n): n is DatabaseSchemaManagedViewTable => n.type === 'managed_view')
            },
            { resultEqualityCheck: objectsEqual },
        ],
        endpointTables: [
            (s) => [s.allTables],
            (allTables: DatabaseSchemaTable[]): DatabaseSchemaEndpointTable[] => {
                return allTables.filter((n): n is DatabaseSchemaEndpointTable => n.type === 'endpoint')
            },
            { resultEqualityCheck: objectsEqual },
        ],
        latestEndpointTables: [
            (s) => [s.endpointTables],
            (endpointTables: DatabaseSchemaEndpointTable[]): DatabaseSchemaEndpointTable[] => {
                const grouped: Record<string, DatabaseSchemaEndpointTable> = {}
                for (const table of endpointTables) {
                    const match = table.name.match(/^(.+)_v(\d+)$/)
                    if (!match) {
                        continue
                    }
                    const [, baseName, versionStr] = match
                    const version = parseInt(versionStr, 10)
                    const existing = grouped[baseName]
                    if (!existing) {
                        grouped[baseName] = table
                    } else {
                        const existingMatch = existing.name.match(/_v(\d+)$/)
                        const existingVersion = existingMatch ? parseInt(existingMatch[1], 10) : 0
                        if (version > existingVersion) {
                            grouped[baseName] = table
                        }
                    }
                }
                return Object.values(grouped)
            },
            { resultEqualityCheck: objectsEqual },
        ],
        viewsMap: [
            (s) => [s.views, s.managedViews, s.endpointTables],
            (
                views: DatabaseSchemaViewTable[],
                managedViews: DatabaseSchemaManagedViewTable[],
                endpointTables: DatabaseSchemaEndpointTable[]
            ): Record<string, DatabaseSchemaViewTable | DatabaseSchemaManagedViewTable | DatabaseSchemaEndpointTable> =>
                toMapByName([...views, ...managedViews, ...endpointTables]),
            { resultEqualityCheck: objectsEqual },
        ],
        viewsMapById: [
            (s) => [s.views, s.managedViews, s.endpointTables],
            (
                views: DatabaseSchemaViewTable[],
                managedViews: DatabaseSchemaManagedViewTable[],
                endpointTables: DatabaseSchemaEndpointTable[]
            ): Record<string, DatabaseSchemaViewTable | DatabaseSchemaManagedViewTable | DatabaseSchemaEndpointTable> =>
                toMapById([...views, ...managedViews, ...endpointTables]),
            { resultEqualityCheck: objectsEqual },
        ],
    }),
    listeners(({ actions, values }) => ({
        refreshDatabaseSchema: () => {
            actions.loadDatabase({ force: true })
        },
        hydrateTableFields: async ({ tableNames }) => {
            const requestConnectionId = values.connectionId ?? undefined
            const tables = values.database?.tables ?? {}
            const toLoad = tableNames.filter((name) => {
                const status = values.tableFieldsStatus[name]
                if (status === 'loading' || status === 'loaded' || status === 'missing') {
                    return false
                }
                const table = tables[name]
                // Unknown tables can't be hydrated; tables with fields already are.
                return !!table && Object.keys(table.fields).length === 0
            })
            if (values.databaseFieldsComplete || toLoad.length === 0) {
                return
            }

            const epoch = latestDatabaseLoadEpoch
            actions.hydrateTableFieldsStart(toLoad)
            try {
                const response = await performQuery(
                    setLatestVersionsOnQuery({
                        kind: NodeKind.DatabaseSchemaQuery,
                        connectionId: requestConnectionId,
                        tables: toLoad,
                    }) as DatabaseSchemaQuery
                )
                if (!databaseTableListLogic.isMounted()) {
                    return
                }
                // A newer full/shallow load replaced the store while we were fetching — its tables
                // (and any statuses) supersede this response.
                if (epoch !== latestDatabaseLoadEpoch || (values.connectionId ?? undefined) !== requestConnectionId) {
                    return
                }
                actions.hydrateTableFieldsSuccess(toLoad, response.tables ?? {})
                // Once every table's fields are in the store, it's equivalent to a full load.
                const tablesNow = values.database?.tables ?? {}
                const statusNow = values.tableFieldsStatus
                const allLoaded = Object.values(tablesNow).every(
                    (table) =>
                        Object.keys(table.fields).length > 0 ||
                        statusNow[table.name] === 'loaded' ||
                        statusNow[table.name] === 'missing'
                )
                if (allLoaded) {
                    actions.setDatabaseFieldsComplete(true)
                }
            } catch {
                if (!databaseTableListLogic.isMounted()) {
                    return
                }
                // Same staleness guard as the success path: a rejection from a superseded request
                // must not stamp errors onto the schema that replaced it.
                if (epoch !== latestDatabaseLoadEpoch || (values.connectionId ?? undefined) !== requestConnectionId) {
                    return
                }
                actions.hydrateTableFieldsFailure(toLoad)
            }
        },
        loadDatabaseSuccess: async ({ payload }, breakpoint) => {
            if (!payload?.shallow || values.databaseFieldsComplete) {
                return
            }
            // A shallow load renders the table tree immediately; upgrade to the full schema in the
            // background so every other consumer of this shared store (taxonomic filters, join
            // modal, insights) still converges on complete field data. The delay lets tables the
            // user expands right away hydrate through their own small requests first; tables
            // already loaded or loading are skipped by the upgrade.
            await breakpoint(3000)
            actions.ensureAllTableFields()
        },
        ensureAllTableFields: () => {
            if (values.databaseFieldsComplete && values.database) {
                return
            }
            // A full (non-shallow) load is already in flight and will land complete fields.
            if (values.databaseLoading && !inFlightDatabaseLoadIsShallow) {
                return
            }
            const tables = values.database?.tables
            if (tables && Object.keys(tables).length > 0) {
                // Upgrade in place: hydrating every table merges fields into the store without
                // flipping `databaseLoading`, so consumers keep rendering the shallow schema
                // meanwhile. Tables already loading/loaded are skipped, errored ones retried.
                actions.hydrateTableFields(Object.keys(tables))
                return
            }
            // Nothing loaded yet. A shallow request may be in flight under the same key; force a
            // fresh full request rather than piggybacking on it.
            actions.loadDatabase({ force: inFlightDatabaseLoadIsShallow && !!inFlightDatabaseLoadPromise })
        },
        // Reload immediately: the cached `database` still holds the connection's schema, and
        // consumers that only load when `database` is empty would otherwise never refetch it.
        resetConnectionScope: () => {
            actions.loadDatabase()
        },
    })),
])
