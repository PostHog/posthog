const meta: Meta = {
    component: App,
    title: 'Scenes-App/Data Management/Property Definitions',
    parameters: {
        layout: 'fullscreen',
        viewMode: 'story',
        mockDate: '2026-03-31',
    },
    decorators: [
        mswDecorator({
            get: {
                '/api/projects/:team_id/property_definitions/': ({ request }) => {
                    const params = new URL(request.url).searchParams
                    const verified = params.get('verified')
                    const inUse = params.get('in_use')
                    const isPerson = params.get('type') === 'person'
                    const source = isPerson ? MOCK_PERSON_PROPERTY_DEFINITIONS : MOCK_PROPERTY_DEFINITIONS
                    let results = source.results

                    if (verified === 'true') {
                        results = results.filter((p) => p.verified === true)
                    } else if (verified === 'false') {
                        results = results.filter((p) => !p.verified)
                    }
                    if (inUse === 'true') {
                        results = results.filter((p) => Object.keys(MOCK_USAGE_BY_NAME[p.name]?.usage ?? {}).length > 0)
                    } else if (inUse === 'false') {
                        results = results.filter(
                            (p) => Object.keys(MOCK_USAGE_BY_NAME[p.name]?.usage ?? {}).length === 0
                        )
                    }

                    return [200, { ...source, results, count: results.length }]
                },
                '/api/projects/:team_id/property_definitions/usage_summary/': ({ request }) => {
                    const names: string[] = JSON.parse(new URL(request.url).searchParams.get('names') || '[]')
                    return [
                        200,
                        {
                            profiles_total: 24500,
                            results: names.map((name) => {
                                const entry = MOCK_USAGE_BY_NAME[name] ?? { usage: {}, profiles_percentage: null }
                                return {
                                    name,
                                    usage: entry.usage,
                                    total_usage: Object.values(entry.usage).reduce((a, b) => a + b, 0),
                                    profiles_percentage: entry.profiles_percentage,
                                }
                            }),
                        },
                    ]
                },
            },
        }),
    ],
}
