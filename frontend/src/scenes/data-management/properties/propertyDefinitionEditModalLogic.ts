export interface PropertyDefinitionEditModalProps {
    propertyDefinition: EnterprisePropertyDefinitionApi
    onClose: () => void
    onSave: (propertyDefinition: EnterprisePropertyDefinitionApi) => void
}

export interface PropertyDefinitionEditForm {
    description: string
    hidden: boolean
    property_type: PropertyDefinitionTypeEnumApi | null
    tags: string[]
    verified: boolean
}

const getPropertyDefinitionEditForm = (
    propertyDefinition: EnterprisePropertyDefinitionApi
): PropertyDefinitionEditForm => ({
    description: propertyDefinition.description ?? '',
    hidden: propertyDefinition.hidden ?? false,
    property_type: propertyDefinition.property_type || null,
    tags: propertyDefinition.tags?.filter((tag): tag is string => typeof tag === 'string') ?? [],
    verified: propertyDefinition.verified ?? false,
})

