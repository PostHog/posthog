export const propertyDefinitionsTableLogic = kea<propertyDefinitionsTableLogicType>([
    path(['scenes', 'data-management', 'properties', 'propertyDefinitionsTableLogic']),
    props({} as PropertyDefinitionsTableLogicProps),
    key((props) => props.key || 'scene'),
    connect(() => ({
        values: [groupsModel, ['groupTypes', 'aggregationLabel'], teamLogic, ['currentProjectId']],
    })),
    actions({
        loadPropertyDefinitions: (url: string | null = '') => ({
            url,
        }),
        setFilters: (filters: Partial<Filters>) => ({ filters }),
        setHoveredDefinition: (definitionKey: string | null) => ({ definitionKey }),
        setOpenedDefinition: (id: string | null) => ({ id }),
        setLocalPropertyDefinition: (definition: PropertyDefinition) => ({ definition }),
        setPropertyType: (propertyType: string) => ({ propertyType }),
        loadQueryUsageByName: true,
    }),
    reducers({
        filters: [
            {
                property: '',
                type: 'event',
            } as Filters,
            {
                setFilters: (state, { filters }) => ({
                    ...state,
                    ...filters,
                }),
            },
        ],
        hoveredDefinition: [
            null as string | null,
            {
                setHoveredDefinition: (_, { definitionKey }) => definitionKey,
            },
        ],
    }),
    selectors({
        propertyTypeOptions: [
            (s) => [s.groupTypes, s.aggregationLabel],
            (
                groupTypes: Map<import('~/types').GroupTypeIndex, import('~/types').GroupType>,
                aggregationLabel: (
                    groupTypeIndex: number | null | undefined,
                    deferToUserWording?: boolean
                ) => import('../../../models/groupsModel').Noun
            ) => {
                const groupChoices: Array<LemonSelectOption<string>> = Array.from(groupTypes.values()).map((type) => ({
                    label: `${capitalizeFirstLetter(aggregationLabel(type.group_type_index).singular)} properties`,
                    value: `group::${type.group_type_index}`,
                }))
                return [
                    { label: 'Event properties', value: 'event::' } as LemonSelectOption<string>,
                    { label: 'Person properties', value: 'person::' } as LemonSelectOption<string>,
                ].concat(groupChoices)
            },
        ],
    }),
    loaders(({ values, cache }) => ({
        queryUsageByName: [
            null as Record<string, number> | null,
            {
                loadQueryUsageByName: async (_, breakpoint) => {
                    // Read the type from the loaded page's URL, since the filters can change before it loads
                    const { type = 'event', group_type_index = null } = combineUrl(
                        values.propertyDefinitions.current ?? ''
                    ).searchParams
                    const entries = usageMetricsEntries(
                        values.propertyDefinitions.results.map((definition) => definition.name),
                        type,
                        group_type_index === null ? null : Number(group_type_index)
                    )
                    if (!entries) {
                        return null
                    }
                    // The column falls back to a dash, so a failed request shouldn't toast on every page load
                    try {
                        const response = await propertyDefinitionsUsageMetricsCreate(String(values.currentProjectId), {
                            properties: entries,
                        })
                        breakpoint()
                        return Object.fromEntries(
                            response.results.map((result) => [result.name, result.query_usage_30_day])
                        )
                    } catch (error) {
                        if (error instanceof Error && isBreakpoint(error)) {
                            throw error
                        }
                        return null
                    }
                },
            },
        ],
        propertyDefinitions: [
            {
                count: 0,
                next: undefined,
                current: undefined,
                previous: undefined,
                results: [],
            } as PropertyDefinitionsPaginatedResponse,
            {
                loadPropertyDefinitions: async ({ url }, breakpoint) => {
                    if (url && url in (cache.apiCache ?? {})) {
                        return cache.apiCache[url]
                    }

                    if (!url) {
                        url = api.propertyDefinitions.determineListEndpoint({})
                    }
                    cache.propertiesStartTime = performance.now()
                    await breakpoint(200)
                    // nosemgrep: prefer-codegen-api -- Legacy raw API call with a URL built at runtime and an unchecked response type. Use a generated function if one covers this endpoint.
                    const response = await api.get(url)
                    breakpoint()

                    const currentUrl = `${normalizePropertyDefinitionEndpointUrl(url)}`
                    cache.apiCache = {
                        ...cache.apiCache,
                        [currentUrl]: {
                            ...response,
                            previous: normalizePropertyDefinitionEndpointUrl(response.previous),
                            next: normalizePropertyDefinitionEndpointUrl(response.next),
                            current: currentUrl,
                            page:
                                Math.floor(
                                    (combineUrl(url).searchParams.offset ?? 0) / EVENT_PROPERTY_DEFINITIONS_PER_PAGE
                                ) + 1,
                        },
                    }
                    return cache.apiCache[url]
                },
                setLocalPropertyDefinition: ({ definition }) => {
                    if (!values.propertyDefinitions.current) {
                        return values.propertyDefinitions
                    }
                    // Update cache as well
                    cache.apiCache = {
                        ...cache.apiCache,
                        [values.propertyDefinitions.current]: {
                            ...values.propertyDefinitions,
                            results: values.propertyDefinitions.results.map((d) =>
                                d.id === definition.id ? definition : d
                            ),
                        },
                    }
                    return cache.apiCache[values.propertyDefinitions.current]
                },
            },
        ],
    })),
    selectors(() => ({
        showVerifiedFilter: [
            (s) => [s.propertyDefinitions],
            (propertyDefinitions: PropertyDefinitionsPaginatedResponse): boolean =>
                propertyDefinitions.results.length > 0 && 'verified' in propertyDefinitions.results[0],
        ],
    })),
    listeners(({ actions, values, cache }) => ({
        setFilters: async (_, breakpoint) => {
            await breakpoint(500)
            const params: Record<string, any> = {
                offset: 0,
                search: values.filters.property,
                type: values.filters.type,
                group_type_index: values.filters.group_type_index,
                verified: values.filters.verified,
            }
            actions.loadPropertyDefinitions(
                normalizePropertyDefinitionEndpointUrl(values.propertyDefinitions.current, params, true)
            )
        },
        loadPropertyDefinitionsSuccess: () => {
            actions.loadQueryUsageByName()
            if (cache.propertiesStartTime !== undefined) {
                posthog.capture('event property definitions page load succeeded', {
                    load_time: performance.now() - cache.propertiesStartTime,
                    num_results: values.propertyDefinitions.results.length,
                })
                cache.propertiesStartTime = undefined
            }
        },
        loadPropertyDefinitionsFailure: ({ error }) => {
            if (cache.propertiesStartTime !== undefined) {
                posthog.capture('event property definitions page load failed', {
                    load_time: performance.now() - cache.propertiesStartTime,
                    error: error ?? 'There was an unknown error fetching property definitions.',
                })
                cache.propertiesStartTime = undefined
            }
        },
        setPropertyType: ({ propertyType }) => {
            const [type, index] = propertyType.split('::')
            actions.setFilters({
                type: type,
                group_type_index: index ? +index : null,
            })
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.propertyDefinitions()]: (_, searchParams) => {
            if (values.propertyDefinitionsLoading) {
                return
            }
            // Parse verified as boolean if present
            const parsedParams = {
                ...searchParams,
                verified:
                    searchParams.verified !== undefined
                        ? searchParams.verified === 'true' || searchParams.verified === true
                        : undefined,
            }
            if (!objectsEqual(cleanFilters(values.filters), cleanFilters(parsedParams))) {
                actions.setFilters(parsedParams as Filters)
            } else if (!values.propertyDefinitions.results.length) {
                actions.loadPropertyDefinitions()
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setFilters: () => {
            const nextValues = cleanFilters(values.filters)
            const urlValues = cleanFilters(router.values.searchParams)
            if (!objectsEqual(nextValues, urlValues)) {
                return [router.values.location.pathname, removeDefaults(nextValues)]
            }
        },
    })),
])
