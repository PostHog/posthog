/** Watches a marketing analytics tile's dataNodeLogic and re-reads it while the precompute is not ready.
 *
 * A not-ready read enqueues a background warm, but the cached not-ready response keeps coming back until
 * someone forces a refresh. This forces one on an interval until the data arrives or the budget runs out. */
export const marketingAnalyticsPrecomputeLogic: LogicWrapper<marketingAnalyticsPrecomputeLogicType> =
    kea<marketingAnalyticsPrecomputeLogicType>([
        props({} as DataNodeLogicProps),
        key((props) => props.key),
        path((key) => ['scenes', 'marketing-analytics', 'marketingAnalyticsPrecomputeLogic', key]),
        connect((props: DataNodeLogicProps) => ({
            values: [dataNodeLogic(props), ['response', 'responseLoading'], teamLogic, ['currentTeamId']],
            actions: [dataNodeLogic(props), ['loadData', 'loadDataSuccess', 'loadDataFailure', 'setResponseSuccess']],
        })),
        actions({
            scheduleRecheck: true,
            recheck: true,
            resetPollBudget: true,
            resetPrecomputeState: true,
            setNotReady: (notReady: boolean) => ({ notReady }),
        }),
        reducers({
            polls: [
                0,
                {
                    recheck: (state) => state + 1,
                    resetPollBudget: () => 0,
                    resetPrecomputeState: () => 0,
                    loadDataSuccess: (state, { response }) => (isNotReady(response) ? state : 0),
                    setResponseSuccess: (state, { response }) => (isNotReady(response) ? state : 0),
                },
            ],
            // Held here, not read off the response: dataNodeLogic clears the response when a re-read fails, and
            // the banner should stay up through our own re-reads instead of flashing a loading state.
            notReady: [
                false,
                {
                    setNotReady: (_, { notReady }) => notReady,
                    resetPrecomputeState: () => false,
                    loadDataSuccess: (_, { response }) => isNotReady(response),
                    // Dashboards hand fresh cachedResults to the tile without a load.
                    setResponseSuccess: (_, { response }) => isNotReady(response),
                },
            ],
        }),
        selectors({
            autoRefreshing: [
                (s) => [s.notReady, s.polls, s.currentTeamId],
                // Shared and exported views have no team loaded, so a forced read there returns nothing.
                (notReady: boolean, polls: number, currentTeamId: number | null): boolean =>
                    notReady && currentTeamId !== null && polls < PRECOMPUTE_MAX_POLLS,
            ],
            latestDayComputedAt: [
                (s) => [s.response],
                (response: AnyResponseType | null): string | null =>
                    (response as { latestDayComputedAt?: string } | null)?.latestDayComputedAt ?? null,
            ],
        }),
        sharedListeners(({ actions, cache, props }) => ({
            handleResponse: ({ response }: { response: AnyResponseType | null }) => {
                if (!isNotReady(response) && cache.polls > 0) {
                    posthog.capture('marketing analytics precompute auto refresh', {
                        outcome: 'ready',
                        polls: cache.polls,
                        query_kind: props.query?.kind,
                    })
                    cache.polls = 0
                }
                actions.scheduleRecheck()
            },
        })),
        listeners(({ actions, values, cache, props, sharedListeners }) => ({
            scheduleRecheck: () => {
                if (!values.autoRefreshing) {
                    cache.disposables.dispose('precomputeRecheck')
                    if (values.notReady && cache.polls > 0) {
                        posthog.capture('marketing analytics precompute auto refresh', {
                            outcome: 'gave_up',
                            polls: cache.polls,
                            query_kind: props.query?.kind,
                        })
                        cache.polls = 0
                    }
                    return
                }
                cache.disposables.add(() => {
                    const timerId = window.setTimeout(() => {
                        // Drop the spent timer, so showing the tab again does not arm a second one.
                        cache.disposables.dispose('precomputeRecheck')
                        actions.recheck()
                    }, PRECOMPUTE_POLL_INTERVAL_MS)
                    return () => window.clearTimeout(timerId)
                }, 'precomputeRecheck')
            },
            recheck: () => {
                cache.recheckLoad = true
                cache.polls = values.polls
                actions.loadData('force_blocking')
            },
            loadData: () => {
                if (cache.recheckLoad) {
                    cache.recheckLoad = false
                    return
                }
                cache.disposables.dispose('precomputeRecheck')
                cache.polls = 0
                actions.resetPrecomputeState()
            },
            loadDataSuccess: sharedListeners.handleResponse,
            setResponseSuccess: sharedListeners.handleResponse,
            loadDataFailure: () => {
                actions.scheduleRecheck()
            },
        })),
        propsChanged(({ actions, cache, props }, oldProps) => {
            // Dashboards hand a new query's cachedResults without a load, so nothing else resets a spent budget.
            if (!compareDataNodeQuery(props.query, oldProps.query, { ignoreVisualizationOnlyChanges: true })) {
                cache.polls = 0
                actions.resetPollBudget()
                actions.scheduleRecheck()
            }
        }),
        afterMount(({ actions, values }) => {
            // The tile may have loaded before this logic mounted, as a dashboard tile does from cachedResults. Its
            // warm may already be done, so the first re-read goes out now instead of after an interval.
            actions.setNotReady(!values.responseLoading && isNotReady(values.response))
            if (values.autoRefreshing) {
                actions.recheck()
            } else {
                actions.scheduleRecheck()
            }
        }),
        beforeUnmount(({ values, props }) => {
            if (values.autoRefreshing && values.polls > 0) {
                posthog.capture('marketing analytics precompute auto refresh', {
                    outcome: 'abandoned',
                    polls: values.polls,
                    query_kind: props.query?.kind,
                })
            }
        }),
    ])
