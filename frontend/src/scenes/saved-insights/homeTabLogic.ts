import { MakeLogicType, connect, kea, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { dashboardTemplatesList, dashboardsCreate } from 'products/dashboards/frontend/generated/api'
import type { DashboardApi } from 'products/dashboards/frontend/generated/api.schemas'
import { DashboardTemplatesListScope } from 'products/dashboards/frontend/generated/api.schemas'

import { teamLogic } from '../teamLogic'
import { urls } from '../urls'

const FALLBACK_TEMPLATE_KEY = 'Product analytics'

const NAMED_TEMPLATE_KEYS = ['SaaS product', 'E-commerce', 'Mobile app']

export function buildHomeTabAiPrompt(freeText: string): string {
    return (
        `Build me a Home tab dashboard for my product analytics. My product: ${freeText}. ` +
        `Create the insights that make sense for it, then pin them to a dashboard so I can use it as my Home tab.`
    )
}

export type HomeTabTemplateMatch = { action: 'use_template'; templateKey: string } | { action: 'ai_handoff' }

// Pure so the matching decision can be tested without mocking any network calls.
export function resolveHomeTabTemplateMatch({
    templateKey,
    freeText,
    searchResultTemplateNames,
}: {
    templateKey: string
    freeText?: string
    searchResultTemplateNames: (string | null | undefined)[]
}): HomeTabTemplateMatch {
    if (NAMED_TEMPLATE_KEYS.includes(templateKey)) {
        return { action: 'use_template', templateKey }
    }
    if (!freeText) {
        return { action: 'use_template', templateKey: FALLBACK_TEMPLATE_KEY }
    }
    // Exclude the fallback template so it's never reported as a search match.
    const matchedTemplateName = searchResultTemplateNames.find((name) => name && name !== FALLBACK_TEMPLATE_KEY)
    return matchedTemplateName ? { action: 'use_template', templateKey: matchedTemplateName } : { action: 'ai_handoff' }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface homeTabLogicValues {
    currentTeamId: number | null // teamLogic
    homeTabDashboard: DashboardApi | null
    homeTabDashboardLoading: boolean
    selectedTemplateKey: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface homeTabLogicActions {
    updateCurrentTeam: (payload: Partial<import('../../types').TeamType>) => Partial<import('../../types').TeamType> // teamLogic
    createHomeTabDashboard: ({
        templateKey,
        label,
        freeText,
    }: {
        label: string
        templateKey: string
        freeText?: string
    }) => {
        templateKey: string
        label: string
        freeText?: string
    }
    createHomeTabDashboardFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    createHomeTabDashboardSuccess: (
        homeTabDashboard: DashboardApi | null,
        payload?: {
            templateKey: string
            label: string
            freeText?: string
        }
    ) => {
        homeTabDashboard: DashboardApi | null
        payload?: {
            templateKey: string
            label: string
            freeText?: string
        }
    }
}

export type homeTabLogicType = MakeLogicType<homeTabLogicValues, homeTabLogicActions>

export const homeTabLogic = kea<homeTabLogicType>([
    path(['scenes', 'saved-insights', 'homeTabLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [teamLogic, ['updateCurrentTeam']],
    })),
    reducers({
        // Tracks which template button is in flight so the picker can show a spinner on the
        // clicked button while disabling the others via homeTabDashboardLoading.
        selectedTemplateKey: [
            null as string | null,
            {
                createHomeTabDashboard: (_, { templateKey }) => templateKey,
                createHomeTabDashboardSuccess: () => null,
                createHomeTabDashboardFailure: () => null,
            },
        ],
    }),
    loaders(({ values, actions }) => ({
        homeTabDashboard: [
            null as DashboardApi | null,
            {
                createHomeTabDashboard: async ({
                    templateKey,
                    label,
                    freeText,
                }: {
                    templateKey: string
                    label: string
                    freeText?: string
                }) => {
                    const needsSearch = !NAMED_TEMPLATE_KEYS.includes(templateKey) && !!freeText
                    const searchResultTemplateNames = needsSearch
                        ? (
                              await dashboardTemplatesList(String(values.currentTeamId), {
                                  scope: DashboardTemplatesListScope.Global,
                                  search: freeText,
                              })
                          ).results.map((template) => template.template_name)
                        : []

                    const match = resolveHomeTabTemplateMatch({ templateKey, freeText, searchResultTemplateNames })

                    if (match.action === 'ai_handoff') {
                        // No template fits well enough, so build one with PostHog AI instead of
                        // defaulting to the generic template.
                        router.actions.push(urls.ai(undefined, buildHomeTabAiPrompt(freeText!)))
                        posthog.capture('home tab ai handoff', { free_text_length: freeText!.length })
                        return null
                    }

                    const dashboard = await dashboardsCreate(String(values.currentTeamId), {
                        name: label,
                        use_template: match.templateKey,
                        pinned: true,
                    })
                    actions.updateCurrentTeam({ home_tab_dashboard: dashboard.id })
                    // Wire format: pinned event and property names, do not rename without a migration plan.
                    posthog.capture('home tab template selected', { template: match.templateKey })
                    return dashboard
                },
            },
        ],
    })),
])
