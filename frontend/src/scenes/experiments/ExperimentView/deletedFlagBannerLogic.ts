import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import api from 'lib/api'
import { ActivityLogItem, userNameForLogItem } from 'lib/components/ActivityLog/humanizeActivity'
import { teamLogic } from 'scenes/teamLogic'

import { Experiment, FeatureFlagBasicType, FeatureFlagType } from '~/types'

import { featureFlagsActivityRetrieve } from 'products/feature_flags/frontend/generated/api'

import { experimentLogic } from '../experimentLogic'

export interface DeletedFlagBannerLogicProps {
    experimentId: Experiment['id']
    flagId: FeatureFlagBasicType['id']
}

export interface FlagDeletion {
    /** Who deleted the flag, named as the activity log names them. */
    actor: string
    deletedAt: string
    /** The API client that sent the delete, for example `mcp`. */
    client: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface deletedFlagBannerLogicValues {
    currentProjectId: number | string // teamLogic
    flagDeletion: FlagDeletion | null
    flagDeletionLoading: boolean
    restoredFlag: FeatureFlagType | null
    restoredFlagLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface deletedFlagBannerLogicActions {
    loadExperiment: (
        payload?:
            | {
                  triggeredBy?: import('../experimentLogic').ExperimentTriggeredBy
              }
            | undefined
    ) => {
        triggeredBy?: import('../experimentLogic').ExperimentTriggeredBy
    } // experimentLogic
    loadFlagDeletion: () => any
    loadFlagDeletionFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFlagDeletionSuccess: (
        flagDeletion: {
            actor: string
            client: string | null
            deletedAt: string
        } | null,
        payload?: any
    ) => {
        flagDeletion: {
            actor: string
            client: string | null
            deletedAt: string
        } | null
        payload?: any
    }
    restoreFlag: () => any
    restoreFlagFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    restoreFlagSuccess: (
        restoredFlag: FeatureFlagType | null,
        payload?: any
    ) => {
        restoredFlag: FeatureFlagType | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface deletedFlagBannerLogicMeta {
    key: number
}

export type deletedFlagBannerLogicType = MakeLogicType<
    deletedFlagBannerLogicValues,
    deletedFlagBannerLogicActions,
    DeletedFlagBannerLogicProps,
    deletedFlagBannerLogicMeta
>

export const deletedFlagBannerLogic = kea<deletedFlagBannerLogicType>([
    props({} as DeletedFlagBannerLogicProps),
    key((props) => props.flagId),
    path((key) => ['scenes', 'experiments', 'ExperimentView', 'deletedFlagBannerLogic', key]),
    connect((props: DeletedFlagBannerLogicProps) => ({
        values: [teamLogic, ['currentProjectId']],
        actions: [experimentLogic({ experimentId: props.experimentId }), ['loadExperiment']],
    })),
    loaders(({ props, values }) => ({
        flagDeletion: [
            null as FlagDeletion | null,
            {
                loadFlagDeletion: async () => {
                    try {
                        const activity = await featureFlagsActivityRetrieve(
                            String(values.currentProjectId),
                            props.flagId,
                            { limit: 10 }
                        )
                        // The log is newest first, so this is the delete that left the flag deleted.
                        const deletion = activity.results.find((entry) => entry.activity === 'deleted')
                        return deletion
                            ? {
                                  // The generated type leaves `user` untyped. The payload is the one `ActivityLogItem` describes.
                                  actor: userNameForLogItem(deletion as unknown as ActivityLogItem),
                                  deletedAt: deletion.created_at,
                                  client: deletion.client,
                              }
                            : null
                    } catch {
                        // The banner still works without who and when, so a failed read stays quiet.
                        return null
                    }
                },
            },
        ],
        restoredFlag: [
            null as FeatureFlagType | null,
            {
                restoreFlag: async () => {
                    try {
                        // nosemgrep: prefer-codegen-api -- The generated partial update request type has no `deleted` field.
                        const flag: FeatureFlagType = await api.update(
                            `api/projects/${values.currentProjectId}/feature_flags/${props.flagId}`,
                            { deleted: false }
                        )
                        // The response carries the restored key, not the one the delete renamed it to.
                        lemonToast.success(`${flag.key} has been restored`)
                        return flag
                    } catch (error: any) {
                        lemonToast.error(error?.detail || "Couldn't restore this feature flag. Try again.")
                        return null
                    }
                },
            },
        ],
    })),
    listeners(({ actions }) => ({
        restoreFlagSuccess: ({ restoredFlag }) => {
            if (restoredFlag) {
                actions.loadExperiment()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadFlagDeletion()
    }),
])
