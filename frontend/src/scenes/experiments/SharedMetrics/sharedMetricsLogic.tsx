import { MakeLogicType, actions, connect, events, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import api from 'lib/api'
import { teamLogic } from 'scenes/teamLogic'

import { experimentSavedMetricsList } from 'products/experiments/frontend/generated/api'
import type { ExperimentSavedMetricsListMetricType } from 'products/experiments/frontend/generated/api.schemas'

import type { SharedMetric } from './sharedMetricLogic'

export const PAGE_SIZE = 100

export interface SharedMetricsFilters {
    created_by_id?: number[]
    tags?: string[]
    metric_type?: ExperimentSavedMetricsListMetricType
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sharedMetricsLogicValues {
    currentProjectId: number | string // teamLogic
    count: number
    filters: SharedMetricsFilters
    hasActiveFilters: boolean
    page: number
    savingTagsMetricId: SharedMetric['id'] | null
    searchTerm: string
    sharedMetrics: SharedMetric[]
    sharedMetricsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sharedMetricsLogicActions {
    deleteSharedMetric: (metricId: SharedMetric['id']) => {
        metricId: number
    }
    loadSharedMetrics: (_: void) => void
    loadSharedMetricsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSharedMetricsSuccess: (
        sharedMetrics: SharedMetric[],
        payload?: void
    ) => {
        sharedMetrics: SharedMetric[]
        payload?: void
    }
    setCount: (count: number) => {
        count: number
    }
    setFilters: (filters: Partial<SharedMetricsFilters>) => {
        filters: Partial<SharedMetricsFilters>
    }
    setPage: (page: number) => {
        page: number
    }
    setSearchTerm: (searchTerm: string) => {
        searchTerm: string
    }
    updateSharedMetricTags: (
        metricId: SharedMetric['id'],
        tags: string[]
    ) => {
        metricId: number
        tags: string[]
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sharedMetricsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        hasActiveFilters: (filters: SharedMetricsFilters, searchTerm: string) => boolean
    }
}

export type sharedMetricsLogicType = MakeLogicType<
    sharedMetricsLogicValues,
    sharedMetricsLogicActions,
    Record<string, any>,
    sharedMetricsLogicMeta
>

export const sharedMetricsLogic = kea<sharedMetricsLogicType>([
    path(['scenes', 'experiments', 'sharedMetricsLogic']),
    connect(() => ({ values: [teamLogic, ['currentProjectId']] })),

    actions({
        updateSharedMetricTags: (metricId: SharedMetric['id'], tags: string[]) => ({ metricId, tags }),
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        setPage: (page: number) => ({ page }),
        setCount: (count: number) => ({ count }),
        setFilters: (filters: Partial<SharedMetricsFilters>) => ({ filters }),
        deleteSharedMetric: (metricId: SharedMetric['id']) => ({ metricId }),
    }),

    reducers({
        savingTagsMetricId: [
            null as SharedMetric['id'] | null,
            {
                updateSharedMetricTags: (_, { metricId }) => metricId,
                loadSharedMetricsSuccess: () => null,
                loadSharedMetricsFailure: () => null,
            },
        ],
        searchTerm: [
            '',
            {
                setSearchTerm: (_, { searchTerm }) => searchTerm,
            },
        ],
        filters: [
            {} as SharedMetricsFilters,
            {
                setFilters: (state, { filters }) => ({ ...state, ...filters }),
            },
        ],
        page: [
            1,
            {
                setPage: (_, { page }) => page,
                setSearchTerm: () => 1,
                setFilters: () => 1,
            },
        ],
        count: [
            0,
            {
                setCount: (_, { count }) => count,
            },
        ],
    }),

    selectors({
        hasActiveFilters: [
            (s) => [s.filters, s.searchTerm],
            (filters: SharedMetricsFilters, searchTerm: string): boolean =>
                !!searchTerm || !!filters.created_by_id?.length || !!filters.tags?.length || !!filters.metric_type,
        ],
    }),

    loaders(({ values, actions }) => ({
        sharedMetrics: [
            [] as SharedMetric[],
            {
                loadSharedMetrics: async (_: void, breakpoint) => {
                    const { created_by_id, tags, metric_type } = values.filters
                    const response = await experimentSavedMetricsList(String(values.currentProjectId), {
                        limit: PAGE_SIZE,
                        offset: (values.page - 1) * PAGE_SIZE,
                        search: values.searchTerm || undefined,
                        created_by_id: created_by_id?.length ? JSON.stringify(created_by_id) : undefined,
                        tags: tags?.length ? JSON.stringify(tags) : undefined,
                        metric_type,
                    })
                    // Discard stale responses that resolve after a newer search has fired
                    breakpoint()
                    actions.setCount(response.count)
                    return response.results as SharedMetric[]
                },
            },
        ],
    })),

    listeners(({ actions, values }) => ({
        setPage: async () => {
            actions.loadSharedMetrics()
        },
        setFilters: async ({ filters }) => {
            // pinned: analytics event name and properties, renaming breaks dashboards
            posthog.capture('experiment shared metrics filtered', {
                changed_filters: Object.keys(filters),
                created_by_count: values.filters.created_by_id?.length ?? 0,
                tags_count: values.filters.tags?.length ?? 0,
                metric_type: values.filters.metric_type ?? null,
            })
            actions.loadSharedMetrics()
        },
        setSearchTerm: async (_, breakpoint) => {
            await breakpoint(300)
            actions.loadSharedMetrics()
        },
        updateSharedMetricTags: async ({ metricId, tags }) => {
            try {
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. Use experimentSavedMetricsPartialUpdate() from 'products/experiments/frontend/generated/api' instead.
                await api.update(`api/projects/${values.currentProjectId}/experiment_saved_metrics/${metricId}`, {
                    tags,
                })
                actions.loadSharedMetrics()
            } catch {
                lemonToast.error('Failed to save tags')
                actions.loadSharedMetrics()
            }
        },
        deleteSharedMetric: async ({ metricId }) => {
            try {
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. experimentSavedMetricsDestroy() from 'products/experiments/frontend/generated/api' serves this route, but its generated types do not describe this call yet, so fix the endpoint's OpenAPI schema first.
                await api.delete(`api/projects/${values.currentProjectId}/experiment_saved_metrics/${metricId}`)
                lemonToast.success('Shared metric deleted successfully')
                actions.loadSharedMetrics()
            } catch {
                lemonToast.error('Failed to delete shared metric')
            }
        },
    })),

    events(({ actions }) => ({
        afterMount: () => {
            actions.loadSharedMetrics()
        },
    })),
])
