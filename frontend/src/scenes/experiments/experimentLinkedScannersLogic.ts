import { MakeLogicType, actions, afterMount, kea, key, path, props, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { visionScannersList } from 'products/replay_vision/frontend/generated/api'
import type { ReplayScannerApi } from 'products/replay_vision/frontend/generated/api.schemas'

export interface ExperimentLinkedScannersLogicProps {
    experimentId: number
}

// One page is plenty: an experiment realistically has a handful of scanners, and this list only
// drives a banner and a rename-confirm, not a paginated view.
const PAGE_LIMIT = 100

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface experimentLinkedScannersLogicValues {
    hasLinkedScanners: boolean
    linkedScanners: ReplayScannerApi[]
    linkedScannersLoading: boolean
    scannersTargetingVariant: (variantKey: string) => ReplayScannerApi[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface experimentLinkedScannersLogicActions {
    loadLinkedScanners: () => {
        value: true
    }
    loadLinkedScannersFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadLinkedScannersSuccess: (
        linkedScanners: ReplayScannerApi[],
        payload?: {
            value: true
        }
    ) => {
        linkedScanners: ReplayScannerApi[]
        payload?: {
            value: true
        }
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface experimentLinkedScannersLogicMeta {
    key: number
    __keaTypeGenInternalSelectorTypes: {
        hasLinkedScanners: (linkedScanners: ReplayScannerApi[]) => boolean
        scannersTargetingVariant: (linkedScanners: ReplayScannerApi[]) => (variantKey: string) => ReplayScannerApi[]
    }
}

export type experimentLinkedScannersLogicType = MakeLogicType<
    experimentLinkedScannersLogicValues,
    experimentLinkedScannersLogicActions,
    ExperimentLinkedScannersLogicProps,
    experimentLinkedScannersLogicMeta
>

/**
 * The replay scanners that target a given experiment, resolved through the `?experiment_id=` filter.
 * The backend gates that filter on the caller's experiment access, so an unreadable experiment (or
 * one with no scanners) resolves to an empty list rather than leaking scanner existence.
 */
export const experimentLinkedScannersLogic = kea<experimentLinkedScannersLogicType>([
    props({} as ExperimentLinkedScannersLogicProps),
    key((props) => props.experimentId),
    path((key) => ['scenes', 'experiments', 'experimentLinkedScannersLogic', String(key)]),

    actions({
        loadLinkedScanners: true,
    }),

    loaders(({ props }) => ({
        linkedScanners: [
            [] as ReplayScannerApi[],
            {
                loadLinkedScanners: async () => {
                    const teamId = teamLogic.values.currentTeamId
                    if (!teamId) {
                        return []
                    }
                    const response = await visionScannersList(String(teamId), {
                        experiment_id: String(props.experimentId),
                        limit: PAGE_LIMIT,
                    })
                    return response.results ?? []
                },
            },
        ],
    })),

    selectors({
        hasLinkedScanners: [(s) => [s.linkedScanners], (scanners: ReplayScannerApi[]): boolean => scanners.length > 0],
        // Scanners targeting a specific variant key, for naming them in the rename confirm.
        scannersTargetingVariant: [
            (s) => [s.linkedScanners],
            (scanners: ReplayScannerApi[]): ((variantKey: string) => ReplayScannerApi[]) => {
                return (variantKey: string) =>
                    scanners.filter((scanner) =>
                        (scanner.experiment_targeting?.variant_keys ?? []).includes(variantKey)
                    )
            },
        ],
    }),

    afterMount(({ actions }) => {
        actions.loadLinkedScanners()
    }),
])
