/**
 * Checks, once per experiment page, which of the experiment's events can match a recording.
 * Recordings are matched through events carrying a `$session_id`, and an event captured
 * server-side never carries one, so a filter on it can only match zero sessions. Keyed on the
 * experiment id so every recordings surface (the per-variant "View recordings" buttons, the
 * recordings tab) shares a single lookup.
 *
 * Two checks, because they answer different questions. The metric events go to the taxonomy
 * `seen_together` fact, which is per event name and project-wide — the right shape for a metric,
 * whose event means the same thing wherever it is captured. The exposure needs the flag-scoped
 * check instead: the default exposure event is shared by every flag in the project, so the
 * project-wide fact reports it linkable off the client-evaluated flags alone, even for an
 * experiment whose own flag is evaluated server-side. That check also says whether the
 * `$feature/<key>` stand-in the surfaces fall back to can match, so a fallback that is just as
 * empty is not offered in place of the exposure.
 */
export const viewRecordingsLinkabilityLogic = kea<viewRecordingsLinkabilityLogicType>([
    props({} as ViewRecordingsLinkabilityLogicProps),
    key((props) => props.experiment.id ?? 'new'),
    path((key) => ['scenes', 'experiments', 'viewRecordingsLinkabilityLogic', String(key)]),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),
    loaders(({ props, values }) => ({
        seenTogetherMap: [
            null as Record<string, boolean> | null,
            {
                loadSeenTogether: async (): Promise<Record<string, boolean>> => {
                    const eventNames = getSessionLinkabilityEventNames(props.experiment)
                    if (eventNames.length === 0) {
                        return {}
                    }
                    return await api.propertyDefinitions.seenTogether({
                        eventNames,
                        propertyDefinitionName: '$session_id',
                    })
                },
            },
        ],
        flagCoverage: [
            null as ExperimentReplayLinkabilityApi | null,
            {
                loadFlagCoverage: async (): Promise<ExperimentReplayLinkabilityApi | null> => {
                    if (typeof props.experiment.id !== 'number' || !props.experiment.start_date) {
                        return null
                    }
                    try {
                        return await experimentsReplayLinkabilityRetrieve(
                            String(values.currentProjectId),
                            props.experiment.id
                        )
                    } catch (error) {
                        // The surfaces ship ahead of this endpoint, so a bundle can reach a backend
                        // that doesn't serve it yet. Every reader below treats an absent verdict as
                        // linkable, so that degrades quietly.
                        if (isUnavailableEndpointError(error)) {
                            return null
                        }
                        // Every other failure stays a failure. Read as success, a broken scan would
                        // silently restore the project-wide answer this check exists to replace,
                        // with nothing in error tracking to show it.
                        throw error
                    }
                },
            },
        ],
    })),
    selectors({
        /** False while the check is in flight or if it failed — callers fail open to today's behavior. */
        linkabilityLoaded: [
            (s) => [s.seenTogetherMap],
            (seenTogetherMap: Record<string, boolean> | null): boolean => seenTogetherMap !== null,
        ],
        unlinkableEventNames: [
            (s) => [s.seenTogetherMap],
            (seenTogetherMap: Record<string, boolean> | null): Set<string> =>
                unlinkableEventNamesFromSeenTogether(seenTogetherMap),
        ],
        /**
         * Whether this experiment's own exposure events carry a session id, from the flag-scoped
         * check. Null until it lands, and whenever it can't answer — readers fail open on null.
         */
        exposureSessionLinkable: [
            (s) => [s.flagCoverage],
            (flagCoverage: ExperimentReplayLinkabilityApi | null): boolean | null =>
                flagCoverage?.exposure_event_linkable ?? null,
        ],
        /** The same question of the `$feature/<key>` stand-in the surfaces fall back to. */
        exposureFallbackLinkable: [
            (s) => [s.flagCoverage],
            (flagCoverage: ExperimentReplayLinkabilityApi | null): boolean | null =>
                flagCoverage?.flag_property_linkable ?? null,
        ],
    }),
    afterMount(({ actions }) => {
        actions.loadSeenTogether()
        actions.loadFlagCoverage()
    }),
    propsChanged(({ actions, props }, oldProps) => {
        if (
            !objectsEqual(
                getSessionLinkabilityEventNames(props.experiment),
                getSessionLinkabilityEventNames(oldProps.experiment)
            )
        ) {
            actions.loadSeenTogether()
        }
        // The scene mounts before the experiment loads, so the first attempt can see no flag and
        // no start date and skip the scan. Re-ask once either arrives.
        if (
            props.experiment.feature_flag_key !== oldProps.experiment.feature_flag_key ||
            props.experiment.start_date !== oldProps.experiment.start_date
        ) {
            actions.loadFlagCoverage()
        }
    }),
])
