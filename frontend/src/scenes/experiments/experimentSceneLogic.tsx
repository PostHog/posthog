export const EXPERIMENT_TABS = ['metrics', 'settings', 'code', 'variants', 'recordings', 'feedback', 'history'] as const
export type ExperimentTab = (typeof EXPERIMENT_TABS)[number]
export const DEFAULT_EXPERIMENT_TAB: ExperimentTab = 'metrics'

// kea-router coerces numeric-looking params to numbers, so check the type before membership
const isExperimentTab = (tab: unknown): tab is ExperimentTab =>
    typeof tab === 'string' && (EXPERIMENT_TABS as readonly string[]).includes(tab)

const getExperimentTabFromSearchParams = (searchParams: Record<string, any>): ExperimentTab => {
    if (isExperimentTab(searchParams.tab)) {
        return searchParams.tab
    }
    if (searchParams.activity) {
        // Activity-log deep links (?activity=<id>) point at an entry on the history tab
        return 'history'
    }
    return DEFAULT_EXPERIMENT_TAB
}

