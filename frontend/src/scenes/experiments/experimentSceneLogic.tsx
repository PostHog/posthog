export const EXPERIMENT_TABS = ['metrics', 'settings', 'code', 'variants', 'recordings', 'feedback', 'history'] as const
export type ExperimentTab = (typeof EXPERIMENT_TABS)[number]
export const DEFAULT_EXPERIMENT_TAB: ExperimentTab = 'metrics'

// The single source of truth for which tabs an experiment renders, shared by the views and by the
// scene logic that clamps the URL-driven tab. Keep it in sync with the tab lists in ExperimentView
// and LegacyExperimentView — a tab the views render but this omits gets clamped away on load.
export const getAvailableExperimentTabs = (experiment: Experiment, featureFlags: FeatureFlagsSet): ExperimentTab[] => {
    // Legacy experiments render a reduced, read-only view with only these two tabs.
    if (isLegacyExperiment(experiment)) {
        return ['metrics', 'variants']
    }
    const isDraft = !isLaunched(experiment) && !experiment.archived
    return EXPERIMENT_TABS.filter((tab) => {
        switch (tab) {
            case 'code':
                // Implementation code is only meaningful once the experiment is launched.
                return !isDraft
            case 'recordings':
                return !!featureFlags[FEATURE_FLAGS.EXPERIMENT_RECORDINGS_TAB]
            case 'feedback':
                return !!experiment.feature_flag
            default:
                return true
        }
    })
}

// kea-router coerces numeric-looking params to numbers, so check the type before membership
const isExperimentTab = (tab: unknown): tab is ExperimentTab =>
    typeof tab === 'string' && (EXPERIMENT_TABS as readonly string[]).includes(tab)

const getExperimentTabFromSearchParams = (searchParams: Record<string, any>): ExperimentTab => {
    if (isExperimentTab(searchParams.tab)) {
        return searchParams.tab
    }
    if (searchParams.activity) {
        // Activity-log deep links (?activity=<id>) point at an entry on the history tab
        return 'history'
    }
    return DEFAULT_EXPERIMENT_TAB
}

// Resolves the tab a URL asks for, clamped to what this experiment actually renders. The clamp only
// applies once the experiment is loaded: while it loads, availability is provisional, so clamping
// could bounce a valid deep link (e.g. ?tab=code to a launched experiment still reading as the draft
// placeholder). The availableTabs subscription catches the load-completes-after-navigation case.
const resolveExperimentTab = (
    query: Record<string, any>,
    values: { experimentLoaded: boolean; availableTabs: ExperimentTab[] }
): ExperimentTab => {
    const requested = getExperimentTabFromSearchParams(query)
    if (values.experimentLoaded && !values.availableTabs.includes(requested)) {
        return DEFAULT_EXPERIMENT_TAB
    }
    return requested
}

