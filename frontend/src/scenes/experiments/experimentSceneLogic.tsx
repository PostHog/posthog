export const experimentSceneLogic = kea<experimentSceneLogicType>([
    props({} as ExperimentSceneLogicProps),
    path(['scenes', 'experiments', 'experimentSceneLogic']),
    connect(() => ({
        actions: [eventUsageLogic, ['reportExperimentTabViewed']],
        values: [featureFlagLogic, ['featureFlags']],
    })),
    actions({
        setActiveTabKey: (activeTabKey: ExperimentTab) => ({ activeTabKey }),
        setSceneState: (experimentId: Experiment['id'], formMode: FormModes) => ({ experimentId, formMode }),
        setExperimentLogicRef: (
            logic: BuiltLogic<experimentLogicType> | null,
            unmount: null | (() => void),
            logicProps: ExperimentLogicProps | null
        ) => ({
            logic,
            unmount,
            logicProps,
        }),
        setEditMode: (editing: boolean) => ({ editing }),
        resetExperimentState: (experimentConfig: Experiment) => ({ experimentConfig }),
    }),
    reducers({
        // setActiveTabKey is deliberately the only writer, so a listener on it sees every tab
        // change; URL-driven changes are dispatched through it in urlToAction below
        activeTabKey: [
            DEFAULT_EXPERIMENT_TAB as ExperimentTab,
            {
                setActiveTabKey: (_, { activeTabKey }) => activeTabKey,
            },
        ],
        experimentId: [
            (props: ExperimentSceneLogicProps) => props.experimentId ?? 'new',
            {
                setSceneState: (_, { experimentId }) => experimentId,
            },
        ],
        formMode: [
            (props: ExperimentSceneLogicProps) => props.formMode ?? FORM_MODES.update,
            {
                setSceneState: (_, { formMode }) => formMode,
            },
        ],
        experimentLogicRef: [
            null as null | {
                logic: BuiltLogic<experimentLogicType>
                unmount: () => void
                props: ExperimentLogicProps
            },
            {
                setExperimentLogicRef: (_, { logic, unmount, logicProps }) =>
                    logic && unmount && logicProps ? { logic, unmount, props: logicProps } : null,
            },
        ],
    }),
    selectors({
        experimentSelector: [
            (s) => [s.experimentLogicRef],
            (
                experimentLogicRef: {
                    logic: BuiltLogic<experimentLogicType>
                    props: ExperimentLogicProps
                    unmount: () => void
                } | null
            ) => experimentLogicRef?.logic.selectors.experiment,
        ],
        experiment: [
            (s) => [
                (state, props) => {
                    try {
                        return s.experimentSelector?.(state, props)?.(state, props)
                    } catch {
                        return null
                    }
                },
            ],
            (experiment: Experiment | null | undefined): Experiment => (experiment ?? NEW_EXPERIMENT) as Experiment,
        ],
        experimentMissingSelector: [
            (s) => [s.experimentLogicRef],
            (
                experimentLogicRef: {
                    logic: BuiltLogic<experimentLogicType>
                    props: ExperimentLogicProps
                    unmount: () => void
                } | null
            ) => experimentLogicRef?.logic.selectors.experimentMissing,
        ],
        experimentMissing: [
            (s) => [
                (state, props) => {
                    try {
                        return s.experimentMissingSelector?.(state, props)?.(state, props)
                    } catch {
                        return false
                    }
                },
            ],
            (experimentMissing: boolean | undefined): boolean => experimentMissing ?? false,
        ],
        isExperimentLaunchedSelector: [
            (s) => [s.experimentLogicRef],
            (
                experimentLogicRef: {
                    logic: BuiltLogic<experimentLogicType>
                    props: ExperimentLogicProps
                    unmount: () => void
                } | null
            ) => experimentLogicRef?.logic.selectors.isExperimentLaunched,
        ],
        isExperimentLaunched: [
            (s) => [
                (state, props) => {
                    try {
                        return s.isExperimentLaunchedSelector?.(state, props)?.(state, props)
                    } catch {
                        return false
                    }
                },
            ],
            (isExperimentLaunched: boolean | undefined): boolean => isExperimentLaunched ?? false,
        ],
        availableTabs: [
            (s) => [s.experiment, s.featureFlags],
            (experiment: Experiment, featureFlags: FeatureFlagsSet): ExperimentTab[] =>
                getAvailableExperimentTabs(experiment, featureFlags),
        ],
        experimentLoaded: [
            (s) => [s.experiment],
            // While the experiment loads, `experiment` is the NEW_EXPERIMENT placeholder (id 'new'),
            // so tab availability derived from it is only provisional. A numeric id means the real
            // experiment has arrived and its available tabs are trustworthy.
            (experiment: Experiment): boolean => experiment.id !== 'new',
        ],
        breadcrumbs: [
            (s) => [s.experiment, s.experimentId],
            (experiment: Experiment, experimentId: Experiment['id']): Breadcrumb[] => {
                return [
                    {
                        key: Scene.Experiments,
                        name: sceneConfigurations[Scene.Experiments].name || 'Experiments',
                        path: urls.experiments(),
                        iconType: sceneConfigurations[Scene.Experiments].iconType || 'default_icon_type',
                    },
                    {
                        key: [Scene.Experiment, experimentId],
                        name: experiment?.name || 'New Experiment',
                        iconType: sceneConfigurations[Scene.Experiment].iconType || 'default_icon_type',
                    },
                ]
            },
        ],
        [SIDE_PANEL_CONTEXT_KEY]: [
            (s) => [s.experimentId],
            (experimentId: Experiment['id']): SidePanelSceneContext | null => {
                return experimentId && experimentId !== 'new'
                    ? {
                          activity_scope: ActivityScope.EXPERIMENT,
                          activity_item_id: `${experimentId}`,
                      }
                    : null
            },
        ],
        projectTreeRef: [
            (s) => [s.experimentId],
            (experimentId: Experiment['id']): ProjectTreeRef => {
                return { type: 'experiment', ref: experimentId === 'new' ? null : String(experimentId) }
            },
        ],
    }),
    subscriptions(({ values, actions }) => ({
        // Fires when the experiment arrives or changes (a draft and its placeholder can share the
        // same available set, so keying off availableTabs alone would miss the load). Once loaded,
        // its tab set can exclude the URL-driven tab (a launched-only tab on a draft, a legacy
        // experiment's reduced set); route the correction through setActiveTabKey so the URL and the
        // `experiment tab viewed` event track what the view actually renders.
        experiment: () => {
            if (values.experimentLoaded && !values.availableTabs.includes(values.activeTabKey)) {
                actions.setActiveTabKey(DEFAULT_EXPERIMENT_TAB)
            }
        },
    })),
    sharedListeners(({ actions, values }) => ({
        ensureExperimentLogicMounted: () => {
            const currentProps = values.experimentLogicRef?.props
            const desiredExperimentId = values.experimentId ?? 'new'
            const desiredFormMode = values.formMode ?? FORM_MODES.update

            if (
                !values.experimentLogicRef ||
                currentProps?.experimentId !== desiredExperimentId ||
                currentProps?.formMode !== desiredFormMode
            ) {
                const oldRef = values.experimentLogicRef

                const logicProps: ExperimentLogicProps = {
                    experimentId: desiredExperimentId,
                    formMode: desiredFormMode,
                }

                const logic = experimentLogic.build(logicProps)
                const unmount = logic.mount()
                actions.setExperimentLogicRef(logic, unmount, logicProps)

                if (oldRef) {
                    oldRef.unmount()
                }
            }
        },
    })),
    listeners(({ actions, selectors, sharedListeners, values }) => ({
        // LemonTabs fires onChange on every tab click, including the already-active tab, so a
        // dispatch that doesn't change the tab is not a view.
        setActiveTabKey: ({ activeTabKey }, _breakpoint, _action, previousState) => {
            if (values.experimentId !== 'new' && selectors.activeTabKey(previousState) !== activeTabKey) {
                actions.reportExperimentTabViewed(values.experimentId, activeTabKey)
            }
        },
        setSceneState: (payload, breakpoint, action, previousState) => {
            sharedListeners.ensureExperimentLogicMounted(payload, breakpoint, action, previousState)
            values.experimentLogicRef?.logic.actions.loadExperiment({ triggeredBy: 'page_load' })
        },
        setEditMode: (payload, breakpoint, action, previousState) => {
            sharedListeners.ensureExperimentLogicMounted(payload, breakpoint, action, previousState)
            values.experimentLogicRef?.logic.actions.setEditExperiment(payload.editing)
        },
        resetExperimentState: (payload, breakpoint, action, previousState) => {
            sharedListeners.ensureExperimentLogicMounted(payload, breakpoint, action, previousState)
        },
    })),
    trackedActionToUrl(({ values }) => {
        const actionToUrl = ({
            experimentId = values.experimentId,
            formMode = values.formMode,
        }: {
            experimentId?: Experiment['id']
            formMode?: FormModes
        }):
            | [string, Record<string, any> | string | undefined, Record<string, any> | string | undefined]
            | undefined => {
            const id = experimentId ?? 'new'
            const effectiveFormMode =
                id === 'new' && formMode === FORM_MODES.create
                    ? undefined
                    : formMode === FORM_MODES.update
                      ? undefined
                      : formMode

            // 'new' keeps the full search so the ?metric=/?name= prefill survives, while numeric ids
            // keep only the params this scene owns: shared links (?tab=, ?activity=) survive the
            // initial setSceneState, and the create flow still drops the prefill params.
            const currentSearch = router.values.currentLocation.searchParams
            const search =
                id === 'new'
                    ? currentSearch
                    : Object.fromEntries(
                          Object.entries(currentSearch).filter(([key]) => key === 'tab' || key === 'activity')
                      )
            return [urls.experiment(id, effectiveFormMode), search, router.values.hashParams]
        }

        return {
            setSceneState: actionToUrl,
            setActiveTabKey: ({ activeTabKey }) => {
                const searchParams = { ...router.values.searchParams }
                if (activeTabKey === DEFAULT_EXPERIMENT_TAB) {
                    delete searchParams.tab
                } else {
                    searchParams.tab = activeTabKey
                }
                // The activity deep-link param belongs to the history tab; kept on another tab it
                // would resolve the tab straight back to history on the next URL pass.
                if (activeTabKey !== 'history') {
                    delete searchParams.activity
                }
                return [router.values.location.pathname, searchParams, router.values.hashParams, { replace: true }]
            },
        }
    }),
    urlToAction(({ actions, values }) => ({
        '/experiments/:id': ({ id }, query, __, currentLocation, previousLocation) => {
            // Ignore sub-routes like /experiments/shared-metrics/new
            // The :id parameter should only be 'new' or a number, not strings like 'shared-metrics'
            if (!id || (id !== 'new' && isNaN(parseInt(id, 10)))) {
                return
            }

            const didPathChange = currentLocation.initial || currentLocation.pathname !== previousLocation?.pathname
            const targetTab = resolveExperimentTab(query, values)

            if (id && didPathChange) {
                const parsedId = id === 'new' ? 'new' : parseInt(id)
                const formMode = parsedId === 'new' ? FORM_MODES.create : FORM_MODES.update
                const existingProps = values.experimentLogicRef?.props
                const matchesExistingLogic =
                    existingProps?.experimentId === parsedId && existingProps?.formMode === formMode
                const isSameSceneState = values.experimentId === parsedId && values.formMode === formMode

                actions.setEditMode(false)

                if (!currentLocation.initial && matchesExistingLogic && isSameSceneState) {
                    // Same experiment, already mounted — skip the full reload, but still run the
                    // page-load stale check so a warming-up experiment refreshes on in-app return.
                    values.experimentLogicRef?.logic.actions.refreshStaleResultsOnReentry()
                } else {
                    actions.setSceneState(parsedId, formMode)

                    // The setActiveTabKey dispatch below reports tab changes; a landing on the
                    // already-active tab dispatches nothing, so it is reported here instead.
                    if (parsedId !== 'new' && targetTab === values.activeTabKey) {
                        actions.reportExperimentTabViewed(parsedId, targetTab)
                    }

                    if (parsedId === 'new') {
                        // Only reset if we're not already viewing a new experiment (tab switch scenario)
                        const shouldReset = currentLocation.initial || values.experimentId !== 'new'

                        if (shouldReset) {
                            // Clear wizard step before the wizard mounts so it starts on 'about'
                            try {
                                sessionStorage.removeItem(stepStorageKey())
                            } catch {
                                // ignore
                            }
                            actions.resetExperimentState({
                                ...NEW_EXPERIMENT,
                                metrics: query.metric ? [query.metric] : [],
                                name: query.name ?? '',
                            })
                        }
                    }
                }
            }

            if (targetTab !== values.activeTabKey) {
                actions.setActiveTabKey(targetTab)
            }
        },
        '/experiments/:id/:formMode': ({ id, formMode }, query, __, currentLocation, previousLocation) => {
            // Ignore routes where id is not a valid experiment identifier (number or 'new')
            // This prevents matching routes like /experiments/shared-metrics/new
            if (!id || (id !== 'new' && isNaN(parseInt(id, 10)))) {
                return
            }

            const didPathChange = currentLocation.initial || currentLocation.pathname !== previousLocation?.pathname
            const targetTab = resolveExperimentTab(query, values)

            if (id && didPathChange) {
                const parsedId = id === 'new' ? 'new' : parseInt(id)
                const parsedFormMode =
                    formMode && Object.values(FORM_MODES).includes(formMode as FormModes)
                        ? (formMode as FormModes)
                        : parsedId === 'new'
                          ? FORM_MODES.create
                          : FORM_MODES.update
                const existingProps = values.experimentLogicRef?.props
                const matchesExistingLogic =
                    existingProps?.experimentId === parsedId && existingProps?.formMode === parsedFormMode
                const isSameSceneState = values.experimentId === parsedId && values.formMode === parsedFormMode

                actions.setEditMode(false)

                if (!currentLocation.initial && matchesExistingLogic && isSameSceneState) {
                    // Same experiment, already mounted — skip the full reload, but still run the
                    // page-load stale check so a warming-up experiment refreshes on in-app return.
                    values.experimentLogicRef?.logic.actions.refreshStaleResultsOnReentry()
                } else {
                    actions.setSceneState(parsedId, parsedFormMode)
                }
            }

            if (targetTab !== values.activeTabKey) {
                actions.setActiveTabKey(targetTab)
            }
        },
    })),
])
