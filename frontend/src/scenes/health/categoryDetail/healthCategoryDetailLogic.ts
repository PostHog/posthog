export const healthCategoryDetailLogic = kea<healthCategoryDetailLogicType>([
    path((key) => ['scenes', 'health', 'categoryDetail', 'healthCategoryDetailLogic', key]),
    props({} as HealthCategoryDetailLogicProps),
    key((props) => props.category),

    connect({
        values: [teamLogic, ['currentTeamIdStrict']],
    }),

    actions({
        setShowDismissed: (show: boolean) => ({ show }),
        snoozeIssue: (id: string, duration: string) => ({ id, duration }),
        dismissIssue: (id: string) => ({ id }),
        undismissIssue: (id: string) => ({ id }),
        refreshHealthData: true,
    }),

    reducers({
        listVersion: [
            0,
            {
                loadHealthIssues: (state) => state + 1,
            },
        ],
        loadingMoreKind: [
            null as string | null,
            {
                loadMoreIssues: (_, kind) => kind,
                loadMoreIssuesSuccess: () => null,
                loadMoreIssuesFailure: () => null,
            },
        ],
        showDismissed: [
            false,
            {
                setShowDismissed: (_, { show }) => show,
            },
        ],
    }),

    loaders(({ values }) => {
        const fetchKindPage = async (kind: string, limit: number, offset: number): Promise<HealthIssuesResponse> => {
            const params: Record<string, string> = {
                status: 'active',
                kind,
                limit: String(limit),
                offset: String(offset),
            }
            if (!values.showDismissed) {
                params.dismissed = 'false'
            }
            const queryString = new URLSearchParams(params).toString()
            // nosemgrep: prefer-codegen-api -- Legacy raw API call with a URL built at runtime and an unchecked response type. Use a generated function if one covers this endpoint.
            return await api.get(`api/projects/${values.currentTeamIdStrict}/health_issues/?${queryString}`)
        }

        return {
            healthIssues: [
                null as HealthIssuesByKind | null,
                {
                    loadHealthIssues: async (): Promise<HealthIssuesByKind | null> => {
                        try {
                            const pages = await Promise.all(
                                values.kinds.map((kind) => {
                                    const loaded = values.healthIssues?.[kind]?.results.length ?? 0
                                    const limit = Math.min(
                                        Math.max(loaded, HEALTH_ISSUES_PAGE_SIZE),
                                        HEALTH_ISSUES_MAX_LIMIT
                                    )
                                    return fetchKindPage(kind, limit, 0)
                                })
                            )
                            return Object.fromEntries(
                                values.kinds.map((kind, index) => [
                                    kind,
                                    {
                                        results: pages[index].results,
                                        count: pages[index].count,
                                        nextOffset: pages[index].results.length,
                                    },
                                ])
                            )
                        } catch {
                            lemonToast.error('Failed to load health issues')
                            return values.healthIssues
                        }
                    },
                    loadMoreIssues: async (kind: string): Promise<HealthIssuesByKind | null> => {
                        const current = values.healthIssues?.[kind]
                        if (!values.healthIssues || !current) {
                            return values.healthIssues
                        }
                        const version = values.listVersion
                        try {
                            const page = await fetchKindPage(kind, HEALTH_ISSUES_PAGE_SIZE, current.nextOffset)
                            if (values.listVersion !== version || values.healthIssues?.[kind] !== current) {
                                return values.healthIssues
                            }
                            const seen = new Set(current.results.map((issue) => issue.id))
                            return {
                                ...values.healthIssues,
                                [kind]: {
                                    results: [
                                        ...current.results,
                                        ...page.results.filter((issue) => !seen.has(issue.id)),
                                    ],
                                    count: page.count,
                                    nextOffset: current.nextOffset + page.results.length,
                                },
                            }
                        } catch {
                            lemonToast.error('Failed to load more health issues')
                            return values.healthIssues
                        }
                    },
                },
            ],
        }
    }),

    selectors({
        category: [() => [(_, props) => props.category], (category: string): string => category],

        isValidCategory: [(s) => [s.category], (category: string): boolean => category in HEALTH_CATEGORY_CONFIG],

        categoryConfig: [
            (s) => [s.category],
            (category: string) => HEALTH_CATEGORY_CONFIG[category as HealthIssueCategory],
        ],

        detailConfig: [
            (s) => [s.category],
            (category: string) => CATEGORY_DETAIL_CONFIG[category as HealthIssueCategory],
        ],

        kinds: [(s) => [s.category], (category: string): string[] => kindsForCategory(category as HealthIssueCategory)],

        issuesByKind: [
            (s) => [s.healthIssues, s.kinds],
            (healthIssues: HealthIssuesByKind | null, kinds: string[]): KindGroup[] => {
                const groups: KindGroup[] = []
                for (const kind of kinds) {
                    const page = healthIssues?.[kind]
                    if (!page || page.results.length === 0) {
                        continue
                    }
                    groups.push({
                        kind,
                        label: kindToLabel(kind),
                        issues: page.results,
                        count: Math.max(page.count, page.results.length),
                        remaining: Math.max(0, page.count - page.nextOffset),
                        worstSeverity: computeWorstSeverity(page.results),
                    })
                }
                return groups.sort(
                    (a, b) => SEVERITY_ORDER.indexOf(a.worstSeverity) - SEVERITY_ORDER.indexOf(b.worstSeverity)
                )
            },
        ],

        categoryIssues: [
            (s) => [s.issuesByKind],
            (issuesByKind: KindGroup[]): HealthIssue[] => issuesByKind.flatMap((group) => group.issues),
        ],

        nextKindWithMore: [
            (s) => [s.issuesByKind],
            (issuesByKind: KindGroup[]): string | null =>
                issuesByKind.find((group) => group.remaining > 0)?.kind ?? null,
        ],

        statusSummary: [
            (s) => [s.issuesByKind],
            (
                issuesByKind: KindGroup[]
            ): { count: number; worstSeverity: HealthIssueSeverity | null; isHealthy: boolean } => {
                if (issuesByKind.length === 0) {
                    return { count: 0, worstSeverity: null, isHealthy: true }
                }
                return {
                    count: issuesByKind.reduce((total, group) => total + group.count, 0),
                    worstSeverity: issuesByKind[0].worstSeverity,
                    isHealthy: false,
                }
            },
        ],

        breadcrumbs: [
            (s) => [s.categoryConfig],
            (categoryConfig: { label: string; description: string } | undefined): Breadcrumb[] => [
                {
                    key: Scene.Health,
                    name: 'Health',
                    path: urls.health(),
                },
                {
                    key: Scene.HealthCategoryDetail,
                    name: categoryConfig?.label ?? 'Detail',
                },
            ],
        ],
    }),

    listeners(({ actions, values }) => ({
        refreshHealthData: () => {
            actions.loadHealthIssues()
        },
        setShowDismissed: () => {
            actions.loadHealthIssues()
        },
        snoozeIssue: async ({ id, duration }) => {
            try {
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                await api.update(`api/projects/${values.currentTeamIdStrict}/health_issues/${id}/`, {
                    snoozed_until: duration,
                })
                actions.loadHealthIssues()
                healthSummaryLogic.actions.loadHealthSummary()
            } catch {
                lemonToast.error("Couldn't snooze this issue. Try again.")
            }
        },
        dismissIssue: async ({ id }) => {
            try {
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                await api.update(`api/projects/${values.currentTeamIdStrict}/health_issues/${id}/`, {
                    dismissed: true,
                })
                actions.loadHealthIssues()
                healthSummaryLogic.actions.loadHealthSummary()
            } catch {
                lemonToast.error('Failed to dismiss issue')
            }
        },
        undismissIssue: async ({ id }) => {
            try {
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                await api.update(`api/projects/${values.currentTeamIdStrict}/health_issues/${id}/`, {
                    dismissed: false,
                })
                actions.loadHealthIssues()
                healthSummaryLogic.actions.loadHealthSummary()
            } catch {
                lemonToast.error('Failed to undismiss issue')
            }
        },
    })),

    afterMount(({ actions, props: logicProps }) => {
        if (!(logicProps.category in HEALTH_CATEGORY_CONFIG)) {
            router.actions.replace(urls.health())
            return
        }
        const redirectUrl = CATEGORY_DETAIL_CONFIG[logicProps.category as HealthIssueCategory]?.redirectUrl
        if (redirectUrl) {
            router.actions.replace(redirectUrl)
            return
        }
        actions.loadHealthIssues()
    }),
])
