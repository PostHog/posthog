import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api, { ApiError } from 'lib/api'
import { healthSummaryLogic } from 'lib/components/HelpMenu/healthSummaryLogic'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import type { HealthCheckState, HealthChecksResponse } from './types'
import { REFRESH_POLL_COUNT, REFRESH_POLL_INTERVAL_MS } from './types'

/**
 * When each health check last ran for this team, and how to re-run one of them.
 *
 * Split out from healthSceneLogic because the same freshness answer is needed wherever a check
 * result is shown — the Health scene, a category detail page, the Web analytics health tab — and
 * mounting the whole scene logic from a card just to read it would refetch the issue list too.
 */

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface healthCheckFreshnessLogicValues {
    currentTeamIdStrict: number | string // teamLogic
    checkStateByKind: Record<string, HealthCheckState>
    healthChecks: HealthChecksResponse | null
    healthChecksLoading: boolean
    refreshingKinds: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface healthCheckFreshnessLogicActions {
    finishRecheck: (kinds: string[]) => {
        kinds: string[]
    }
    loadHealthChecks: () => any
    loadHealthChecksFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadHealthChecksSuccess: (
        healthChecks: HealthChecksResponse | null,
        payload?: any
    ) => {
        healthChecks: HealthChecksResponse | null
        payload?: any
    }
    recheckKinds: (
        kinds: string[],
        onComplete?: () => void
    ) => {
        kinds: string[]
        onComplete?: () => void
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface healthCheckFreshnessLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        checkStateByKind: (healthChecks: HealthChecksResponse | null) => Record<string, HealthCheckState>
    }
}

export type healthCheckFreshnessLogicType = MakeLogicType<
    healthCheckFreshnessLogicValues,
    healthCheckFreshnessLogicActions,
    Record<string, any>,
    healthCheckFreshnessLogicMeta
>

export const healthCheckFreshnessLogic = kea<healthCheckFreshnessLogicType>([
    path(['scenes', 'health', 'healthCheckFreshnessLogic']),
    connect({
        values: [teamLogic, ['currentTeamIdStrict']],
    }),
    actions({
        recheckKinds: (kinds: string[], onComplete?: () => void) => ({ kinds, onComplete }),
        finishRecheck: (kinds: string[]) => ({ kinds }),
    }),
    reducers({
        refreshingKinds: [
            [] as string[],
            {
                recheckKinds: (state, { kinds }) => Array.from(new Set([...state, ...kinds])),
                finishRecheck: (state, { kinds }) => state.filter((kind) => !kinds.includes(kind)),
            },
        ],
    }),
    loaders(({ values }) => ({
        healthChecks: [
            null as HealthChecksResponse | null,
            {
                loadHealthChecks: async (): Promise<HealthChecksResponse | null> =>
                    await api.get(`api/environments/${values.currentTeamIdStrict}/health_issues/checks/`),
            },
        ],
    })),
    selectors({
        checkStateByKind: [
            (s) => [s.healthChecks],
            (healthChecks: HealthChecksResponse | null): Record<string, HealthCheckState> =>
                Object.fromEntries((healthChecks?.results ?? []).map((check) => [check.kind, check])),
        ],
    }),
    listeners(({ actions }) => ({
        recheckKinds: async ({ kinds, onComplete }, breakpoint) => {
            const url = `api/environments/${teamLogic.values.currentTeamIdStrict}/health_issues/refresh/`
            try {
                await api.create(url, { kinds })
                breakpoint()
                lemonToast.success(`Re-checking ${kinds.length === 1 ? 'this check' : `${kinds.length} checks`}...`, {
                    autoClose: 2000,
                })

                // The detection runs in a worker, so poll for the result rather than guessing how
                // long it takes.
                for (let i = 0; i < REFRESH_POLL_COUNT; i++) {
                    await breakpoint(REFRESH_POLL_INTERVAL_MS)
                    actions.loadHealthChecks()
                    onComplete?.()
                }
                healthSummaryLogic.actions.loadHealthSummary()
                actions.finishRecheck(kinds)
            } catch (error: unknown) {
                actions.finishRecheck(kinds)
                if (error instanceof ApiError && error.status === 429) {
                    lemonToast.warning(
                        `This check was re-checked a moment ago. Try again ${
                            error.formattedRetryAfter ?? 'in a minute'
                        }.`
                    )
                } else {
                    lemonToast.error("Couldn't re-run this check. Try again.")
                }
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadHealthChecks()
    }),
])
