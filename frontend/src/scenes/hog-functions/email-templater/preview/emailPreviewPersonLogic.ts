import { MakeLogicType, actions, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { subscriptions } from 'kea-subscriptions'

import api from 'lib/api'

import { ActorsQuery, NodeKind, ProductKey } from '~/queries/schema/schema-general'
import { AnyPersonScopeFilter } from '~/types'

import { EmailPreviewPerson } from './emailPreview'

const PREVIEW_PERSON_LIMIT = 25

export interface PreviewPerson extends EmailPreviewPerson {
    displayName: string
}

export interface EmailPreviewPersonLogicProps {
    /** Every preview that shares a scope, such as one workflow or one broadcast, renders as the same person. */
    scope: string
}

// The properties column arrives as a JSON string over the query API, but tolerate an object in case
// a caller hands one over already parsed.
function parseProperties(raw: unknown): Record<string, any> {
    if (raw && typeof raw === 'object') {
        return raw as Record<string, any>
    }
    if (typeof raw === 'string') {
        try {
            return JSON.parse(raw)
        } catch {
            return {}
        }
    }
    return {}
}

function parsePerson(row: any[]): PreviewPerson {
    const properties = parseProperties(row[2])
    return {
        id: String(row[0]),
        displayName: row[1]?.display_name || properties.email || String(row[0]),
        properties,
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface emailPreviewPersonLogicValues {
    audience: AnyPersonScopeFilter[]
    persons: PreviewPerson[]
    personsFailed: boolean
    personsLoading: boolean
    previewPerson: PreviewPerson | null
    selectedPersonId: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface emailPreviewPersonLogicActions {
    loadPersons: (_: void) => void
    loadPersonsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadPersonsSuccess: (
        persons: PreviewPerson[],
        payload?: void
    ) => {
        persons: PreviewPerson[]
        payload?: void
    }
    selectPerson: (personId: string | null) => {
        personId: string | null
    }
    setAudience: (audience: AnyPersonScopeFilter[]) => {
        audience: AnyPersonScopeFilter[]
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface emailPreviewPersonLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        previewPerson: (persons: PreviewPerson[], selectedPersonId: string | null) => PreviewPerson | null
    }
}

export type emailPreviewPersonLogicType = MakeLogicType<
    emailPreviewPersonLogicValues,
    emailPreviewPersonLogicActions,
    EmailPreviewPersonLogicProps,
    emailPreviewPersonLogicMeta
>

export const emailPreviewPersonLogic = kea<emailPreviewPersonLogicType>([
    path((key) => ['scenes', 'hog-functions', 'email-templater', 'preview', 'emailPreviewPersonLogic', key]),
    props({} as EmailPreviewPersonLogicProps),
    key((props) => props.scope),

    actions({
        setAudience: (audience: AnyPersonScopeFilter[]) => ({ audience }),
        selectPerson: (personId: string | null) => ({ personId }),
    }),

    reducers({
        audience: [[] as AnyPersonScopeFilter[], { setAudience: (_, { audience }) => audience }],
        selectedPersonId: [
            null as string | null,
            {
                selectPerson: (_, { personId }) => personId,
                // The audience decides who is on offer, so a reload invalidates the old pick.
                loadPersons: () => null,
            },
        ],
        // An empty list and a failed lookup both leave the picker empty, but they mean
        // different things to a sender, so keep them apart.
        personsFailed: [
            false,
            {
                loadPersons: () => false,
                loadPersonsSuccess: () => false,
                loadPersonsFailure: () => true,
            },
        ],
    }),

    loaders(({ values }) => ({
        persons: [
            [] as PreviewPerson[],
            {
                loadPersons: async (_: void, breakpoint) => {
                    // A host hands over its audience right after mounting, so only the last lookup runs.
                    await breakpoint(1)
                    const query: ActorsQuery = {
                        kind: NodeKind.ActorsQuery,
                        // Attributes the query in the ClickHouse query log. Without it the backend
                        // rejects the query outright when DEBUG is on, so the picker stays empty
                        // for anyone running locally.
                        tags: { productKey: ProductKey.WORKFLOWS },
                        // Audiences only offer person-scoped filters, which is all an actors query accepts.
                        properties: values.audience,
                        select: ['id', 'person_display_name -- Person', 'properties'],
                        limit: PREVIEW_PERSON_LIMIT,
                    }
                    let response
                    try {
                        response = await api.query<ActorsQuery>(query)
                    } catch (error) {
                        // A failure from a lookup that a newer one replaced must not end the newer one's loading.
                        breakpoint()
                        throw error
                    }
                    breakpoint()
                    return (response.results ?? []).map(parsePerson)
                },
            },
        ],
    })),

    selectors({
        previewPerson: [
            (s) => [s.persons, s.selectedPersonId],
            (persons: PreviewPerson[], selectedPersonId: string | null): PreviewPerson | null =>
                persons.find((person) => person.id === selectedPersonId) ??
                // Default to someone the email can reach. An audience filter that does not mention
                // email can put a person with no email address first, and that person renders every
                // merge tag blank, so the preview reads as broken rather than as an empty value.
                persons.find((person) => !!person.properties.email) ??
                persons[0] ??
                null,
        ],
    }),

    // Reload on the value rather than on the action, so the first lookup runs on mount.
    subscriptions(({ actions }) => ({
        audience: () => {
            actions.loadPersons()
        },
    })),
])
