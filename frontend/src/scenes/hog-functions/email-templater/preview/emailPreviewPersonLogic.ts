import { EmailPreviewPerson } from './emailPreview'

const PREVIEW_PERSON_LIMIT = 25
const HAS_EMAIL: AnyPersonScopeFilter = {
    key: 'email',
    type: PropertyFilterType.Person,
    operator: PropertyOperator.IsSet,
    value: PropertyOperator.IsSet,
}

export interface PreviewPerson extends EmailPreviewPerson {
    displayName: string
}

export interface EmailPreviewPersonLogicProps {
    /** Every preview that shares a scope, such as one workflow or one broadcast, renders as the same person. */
    scope: string
}

// The properties column arrives as a JSON string over the query API, but tolerate an object in case
// a caller hands one over already parsed.
function parseProperties(raw: unknown): Record<string, any> {
    if (raw && typeof raw === 'object') {
        return raw as Record<string, any>
    }
    if (typeof raw === 'string') {
        try {
            return JSON.parse(raw)
        } catch {
            return {}
        }
    }
    return {}
}

function parsePerson(row: any[]): PreviewPerson {
    const properties = parseProperties(row[2])
    return {
        id: String(row[0]),
        displayName: row[1]?.display_name || properties.email || String(row[0]),
        properties,
    }
}

