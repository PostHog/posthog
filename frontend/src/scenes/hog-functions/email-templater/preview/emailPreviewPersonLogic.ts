export const emailPreviewPersonLogic = kea<emailPreviewPersonLogicType>([
    path((key) => ['scenes', 'hog-functions', 'email-templater', 'preview', 'emailPreviewPersonLogic', key]),
    props({} as EmailPreviewPersonLogicProps),
    key((props) => props.scope),

    actions({
        setAudience: (audience: AnyPersonScopeFilter[]) => ({ audience }),
        selectPerson: (personId: string | null) => ({ personId }),
        pickPerson: (person: PreviewPerson) => ({ person }),
        shufflePerson: true,
        setSearch: (search: string) => ({ search }),
        setCustomProperties: (properties: Record<string, string> | null) => ({ properties }),
        setTriggerEvent: (triggerEvent: string | null) => ({ triggerEvent }),
    }),

    reducers({
        // Null until a host such as a broadcast hands over its audience.
        audience: [null as AnyPersonScopeFilter[] | null, { setAudience: (_, { audience }) => audience }],
        triggerEvent: [null as string | null, { setTriggerEvent: (_, { triggerEvent }) => triggerEvent }],
        selectedPersonId: [
            null as string | null,
            {
                selectPerson: (_, { personId }) => personId,
                pickPerson: (_, { person }) => person.id,
                // The audience decides who is on offer, so a reload invalidates the old pick.
                loadPersons: () => null,
            },
        ],
        customProperties: [
            null as Record<string, string> | null,
            {
                setCustomProperties: (_, { properties }) => properties,
                selectPerson: () => null,
                pickPerson: () => null,
            },
        ],
        // An empty list and a failed lookup both leave the picker empty, but they mean
        // different things to a sender, so keep them apart.
        personsFailed: [
            false,
            {
                loadPersons: () => false,
                loadPersonsSuccess: () => false,
                loadPersonsFailure: () => true,
            },
        ],
    }),

    loaders(({ values }) => ({
        persons: [
            [] as PreviewPerson[],
            {
                loadPersons: async (_: void, breakpoint) => {
                    // A host hands over its audience right after mounting, so only the last lookup runs.
                    await breakpoint(1)
                    const query: ActorsQuery = {
                        kind: NodeKind.ActorsQuery,
                        // Attributes the query in the ClickHouse query log. Without it the backend
                        // rejects the query outright when DEBUG is on, so the picker stays empty
                        // for anyone running locally.
                        tags: { productKey: ProductKey.WORKFLOWS },
                        // Audiences only offer person-scoped filters, which is all an actors query accepts.
                        // Without one, someone with no email address makes a poor preview of an email.
                        properties: values.audience ?? [HAS_EMAIL],
                        select: ['id', 'person_display_name -- Person', 'properties'],
                        limit: PREVIEW_PERSON_LIMIT,
                    }
                    let response
                    try {
                        response = await api.query<ActorsQuery>(query)
                    } catch (error) {
                        // A failure from a lookup that a newer one replaced must not end the newer one's loading.
                        breakpoint()
                        throw error
                    }
                    breakpoint()
                    return (response.results ?? []).map(parsePerson)
                },
                // A person found by search joins the pool, so the pick survives the search closing.
                pickPerson: ({ person }) =>
                    values.persons.some(({ id }) => id === person.id) ? values.persons : [person, ...values.persons],
            },
        ],
        personEvent: [
            null as EmailPreviewPerson['event'] | null,
            {
                loadPersonEvent: async (_, breakpoint) => {
                    const { triggerEvent, chosenPerson } = values
                    if (!triggerEvent || !chosenPerson || chosenPerson.id === CUSTOM_PERSON_ID) {
                        return null
                    }
                    const response = await api.query<EventsQuery>({
                        kind: NodeKind.EventsQuery,
                        tags: { productKey: ProductKey.WORKFLOWS },
                        select: ['properties'],
                        event: triggerEvent,
                        personId: chosenPerson.id,
                        after: '-30d',
                        orderBy: ['timestamp DESC'],
                        limit: 1,
                    })
                    breakpoint()
                    const row = response.results?.[0]
                    return row ? { properties: parseProperties(row[0]) } : null
                },
            },
        ],
        searchResults: [
            [] as PreviewPerson[],
            {
                setSearch: async ({ search }, breakpoint) => {
                    await breakpoint(300)
                    if (!search.trim()) {
                        return []
                    }
                    const response = await api.query<ActorsQuery>({
                        kind: NodeKind.ActorsQuery,
                        tags: { productKey: ProductKey.WORKFLOWS },
                        search,
                        select: ['id', 'person_display_name -- Person', 'properties'],
                        limit: PREVIEW_PERSON_LIMIT,
                    })
                    breakpoint()
                    return (response.results ?? []).map(parsePerson)
                },
            },
        ],
    })),

    listeners(({ actions, values }) => ({
        shufflePerson: () => {
            const others = values.persons.filter(
                (person) => !!person.properties.email && person.id !== values.previewPerson?.id
            )
            if (others.length > 0) {
                actions.selectPerson(others[Math.floor(Math.random() * others.length)].id)
            }
        },
    })),

    selectors({
        chosenPerson: [
            (s) => [s.persons, s.selectedPersonId, s.customProperties],
            (
                persons: PreviewPerson[],
                selectedPersonId: string | null,
                customProperties: Record<string, string> | null
            ): PreviewPerson | null =>
                (customProperties && customPerson(customProperties)) ??
                persons.find((person) => person.id === selectedPersonId) ??
                // Default to someone the email can reach. An audience filter that does not mention
                // email can put a person with no email address first, and that person renders every
                // merge tag blank, so the preview reads as broken rather than as an empty value.
                persons.find((person) => !!person.properties.email) ??
                persons[0] ??
                null,
        ],
        previewPerson: [
            (s) => [s.chosenPerson, s.personEvent],
            (
                chosenPerson: PreviewPerson | null,
                personEvent: EmailPreviewPerson['event'] | null
            ): PreviewPerson | null =>
                chosenPerson && personEvent ? { ...chosenPerson, event: personEvent } : chosenPerson,
        ],
        personEventSource: [
            (s) => [s.triggerEvent, s.chosenPerson],
            (triggerEvent: string | null, chosenPerson: PreviewPerson | null): string =>
                `${triggerEvent}:${chosenPerson?.id}`,
        ],
    }),

    // Reload on the value rather than on the action, so the first lookup runs on mount.
    subscriptions(({ actions }) => ({
        audience: () => {
            actions.loadPersons()
        },
        personEventSource: () => {
            actions.loadPersonEvent(null)
        },
    })),
])
