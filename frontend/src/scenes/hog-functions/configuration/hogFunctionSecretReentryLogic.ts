export const hogFunctionSecretReentryLogic = kea<hogFunctionSecretReentryLogicType>([
    props({} as HogFunctionConfigurationLogicProps),
    key(hogFunctionConfigurationLogicKey),
    path((key) => ['scenes', 'hog-functions', 'configuration', 'hogFunctionSecretReentryLogic', key]),
    connect((props: HogFunctionConfigurationLogicProps) => ({
        values: [hogFunctionConfigurationLogic(props), ['configuration']],
        actions: [
            hogFunctionConfigurationLogic(props),
            ['setConfigurationValue', 'submitConfiguration', 'upsertHogFunctionFailure'],
        ],
    })),
    actions({
        requireSecretReentry: (refusal: SecretReentryRefusal, source: SecretReentrySource, onContinue: () => void) => ({
            refusal,
            source,
            onContinue,
        }),
        openSecretReentry: (prompt: SecretReentryPrompt) => ({ prompt }),
        setSecretValue: (value: string) => ({ value }),
        setSecretEntry: (entryKey: string, value: string) => ({ entryKey, value }),
        cancelSecretReentry: true,
        confirmSecretReentry: true,
        closeSecretReentry: true,
        clearSecretReentry: true,
    }),
    reducers({
        isOpen: [
            false,
            {
                openSecretReentry: () => true,
                closeSecretReentry: () => false,
            },
        ],
        // Kept after close until the modal has animated out, so the closing dialog does not change its content.
        prompt: [
            null as SecretReentryPrompt | null,
            {
                openSecretReentry: (_, { prompt }) => prompt,
                clearSecretReentry: () => null,
            },
        ],
        secretValue: [
            '',
            {
                setSecretValue: (_, { value }) => value,
                openSecretReentry: () => '',
                clearSecretReentry: () => '',
            },
        ],
        secretEntryValues: [
            {} as Record<string, string>,
            {
                setSecretEntry: (state, { entryKey, value }) => ({ ...state, [entryKey]: value }),
                openSecretReentry: () => ({}),
                clearSecretReentry: () => ({}),
            },
        ],
    }),
    selectors({
        confirmDisabledReason: [
            (s) => [s.prompt, s.secretValue, s.secretEntryValues],
            (
                prompt: SecretReentryPrompt | null,
                secretValue: string,
                secretEntryValues: Record<string, string>
            ): string | undefined => {
                if (!prompt) {
                    return undefined
                }
                if (prompt.entryKeys) {
                    return prompt.entryKeys.every((entry) => secretEntryValues[entry]?.trim())
                        ? undefined
                        : 'Enter every value'
                }
                return secretValue.trim() ? undefined : 'Enter the secret'
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        upsertHogFunctionFailure: ({ errorObject }) => {
            const refusal = parseSecretReentryRefusal(errorObject)
            if (refusal) {
                actions.requireSecretReentry(refusal, 'save', () => actions.submitConfiguration())
            }
        },
        requireSecretReentry: ({ refusal, source, onContinue }) => {
            const prompt = secretReentryPrompt(values.configuration, refusal.key, source)
            if (!prompt) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('hog function secret reentry unavailable', { source })
                lemonToast.error(refusal.detail)
                return
            }
            cache.onContinue = onContinue
            actions.openSecretReentry(prompt)
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('hog function secret reentry shown', trackingProperties(prompt))
        },
        cancelSecretReentry: () => {
            if (values.prompt) {
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('hog function secret reentry cancelled', trackingProperties(values.prompt))
            }
            actions.closeSecretReentry()
        },
        confirmSecretReentry: () => {
            const { prompt } = values
            if (!values.isOpen || !prompt || values.confirmDisabledReason) {
                return
            }
            const input = values.configuration.inputs?.[prompt.key]
            const value = prompt.entryKeys
                ? { ...secretEntries(input), ...values.secretEntryValues }
                : values.secretValue
            // Save sends a `secret` input as "keep the stored value", so the entered one drops the flag.
            actions.setConfigurationValue(['inputs', prompt.key], { ...input, secret: false, value })
            // pinned: analytics event name - renaming breaks dashboards
            posthog.capture('hog function secret reentry confirmed', trackingProperties(prompt))
            const onContinue = cache.onContinue as (() => void) | undefined
            cache.onContinue = undefined
            actions.closeSecretReentry()
            onContinue?.()
        },
    })),
])
