/**
 * The API refuses a change that would send a stored secret to a new address until the secret is
 * typed again. This asks for it, writes it into the unsaved form, and retries what was refused.
 */
export const hogFunctionSecretReentryLogic = kea<hogFunctionSecretReentryLogicType>([
    props({} as HogFunctionConfigurationLogicProps),
    key(hogFunctionConfigurationLogicKey),
    path((key) => ['scenes', 'hog-functions', 'configuration', 'hogFunctionSecretReentryLogic', key]),
    connect((props: HogFunctionConfigurationLogicProps) => ({
        values: [hogFunctionConfigurationLogic(props), ['configuration']],
        actions: [
            hogFunctionConfigurationLogic(props),
            ['setConfigurationValue', 'submitConfiguration', 'touchConfigurationField', 'upsertHogFunctionFailure'],
        ],
    })),
    actions({
        requireSecretReentry: (key: string, retry: SecretReentryRetry) => ({ key, retry }),
        setSecretValue: (value: string) => ({ value }),
        setSecretEntry: (entryKey: string, value: string) => ({ entryKey, value }),
        cancelSecretReentry: true,
        confirmSecretReentry: true,
        secretReentered: (retry: SecretReentryRetry) => ({ retry }),
    }),
    reducers({
        request: [
            null as SecretReentryRequest | null,
            {
                requireSecretReentry: (_, { key, retry }) => ({ key, retry }),
                cancelSecretReentry: () => null,
                secretReentered: () => null,
            },
        ],
        secretValue: [
            '',
            {
                setSecretValue: (_, { value }) => value,
                requireSecretReentry: () => '',
                cancelSecretReentry: () => '',
                secretReentered: () => '',
            },
        ],
        secretEntryValues: [
            {} as Record<string, string>,
            {
                setSecretEntry: (state, { entryKey, value }) => ({ ...state, [entryKey]: value }),
                requireSecretReentry: () => ({}),
                cancelSecretReentry: () => ({}),
                secretReentered: () => ({}),
            },
        ],
    }),
    selectors({
        prompt: [
            (s) => [s.request, s.configuration],
            (
                request: SecretReentryRequest | null,
                configuration: HogFunctionConfigurationType
            ): SecretReentryPrompt | null => {
                const schema = request && configuration?.inputs_schema?.find((s) => s.key === request.key)
                if (!request || !schema) {
                    return null
                }
                const label = schema.label || schema.key
                if (schema.type !== 'dictionary') {
                    return { key: schema.key, label, entryKeys: null }
                }
                const entries = secretEntries(configuration.inputs?.[schema.key]) ?? {}
                const entryKeys = Object.keys(entries).filter((entry) => entries[entry] === MASKED_SECRET_VALUE)
                // Without the masked keys there is nothing to list, so the field's own error asks for the value instead.
                return entryKeys.length ? { key: schema.key, label, entryKeys } : null
            },
        ],
        confirmDisabledReason: [
            (s) => [s.prompt, s.secretValue, s.secretEntryValues],
            (
                prompt: SecretReentryPrompt | null,
                secretValue: string,
                secretEntryValues: Record<string, string>
            ): string | undefined => {
                if (!prompt) {
                    return undefined
                }
                if (prompt.entryKeys) {
                    return prompt.entryKeys.every((entry) => secretEntryValues[entry]?.trim())
                        ? undefined
                        : 'Enter every value'
                }
                return secretValue.trim() ? undefined : 'Enter the secret'
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        upsertHogFunctionFailure: ({ errorObject }) => {
            const key = secretReentryKey(errorObject)
            if (key) {
                actions.requireSecretReentry(key, 'save')
            }
        },
        confirmSecretReentry: () => {
            const { prompt, request } = values
            if (!prompt || !request || values.confirmDisabledReason) {
                return
            }
            const input = values.configuration.inputs?.[prompt.key]
            const value = prompt.entryKeys
                ? { ...secretEntries(input), ...values.secretEntryValues }
                : values.secretValue
            // Save sends a `secret` input as "keep the stored value", so the entered one drops the flag.
            actions.setConfigurationValue(['inputs', prompt.key], { ...input, secret: false, value })
            // Clears the refusal the save left on the inputs field, which would otherwise block the retry.
            actions.touchConfigurationField('inputs')
            actions.secretReentered(request.retry)
            if (request.retry === 'save') {
                actions.submitConfiguration()
            }
        },
    })),
])
