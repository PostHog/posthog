// Save and test send the form, so the entered secret goes into the form. Publish sends the staged draft,
// which the form does not hold, so the entered secret goes with the publish request instead.
export type SecretReentrySource = 'save' | 'test' | 'publish'

export type SecretReentryConfiguration = Pick<Partial<HogFunctionConfigurationType>, 'inputs_schema' | 'inputs'>

export type SecretReentryValue = string | Record<string, string>

export type EnteredSecretInputs = Record<string, { value: SecretReentryValue }>

export interface SecretReentryPrompt {
    key: string
    label: string
    // The server's reason for the refusal, which names the hosts the change sends the secret to.
    detail: string
    // The masked entries of a dictionary secret, each of which has to be typed again. Null for a single value.
    entryKeys: string[] | null
    source: SecretReentrySource
}

interface SecretReentryCache {
    onContinue?: (entered: EnteredSecretInputs) => void
    configuration?: SecretReentryConfiguration | null
}

function textEntries(input: CyclotronJobInputType | undefined): Record<string, string> {
    return Object.fromEntries(
        Object.entries(secretEntries(input) ?? {}).filter(
            (entry): entry is [string, string] => typeof entry[1] === 'string'
        )
    )
}

// The dialog types text, so it asks only for a secret stored as text or as a dictionary of text.
function secretReentryPrompt(
    configuration: SecretReentryConfiguration,
    { key, detail }: SecretReentryRefusal,
    source: SecretReentrySource
): SecretReentryPrompt | null {
    const schema = configuration.inputs_schema?.find((s) => s.key === key)
    if (!schema) {
        return null
    }
    const label = schema.label || schema.key
    if (schema.type === 'string') {
        return { key, label, detail, entryKeys: null, source }
    }
    if (schema.type !== 'dictionary') {
        return null
    }
    const entries = textEntries(configuration.inputs?.[key])
    const entryKeys = Object.keys(entries).filter((entry) => entries[entry] === MASKED_SECRET_VALUE)
    return entryKeys.length ? { key, label, detail, entryKeys, source } : null
}

function unavailableMessage(label: string, source: SecretReentrySource): string {
    return source === 'publish'
        ? `The staged changes send ${label} to a new address and need it entered again, which isn't possible here. Discard the draft and make the change in the form.`
        : `Enter ${label} again in the form. Your edits send this secret to a new address.`
}

function trackingProperties(prompt: SecretReentryPrompt): Record<string, string> {
    return { source: prompt.source, kind: prompt.entryKeys ? 'dictionary' : 'single' }
}

