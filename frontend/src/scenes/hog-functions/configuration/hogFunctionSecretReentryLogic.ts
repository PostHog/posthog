export type SecretReentryRetry = 'save' | 'test'

export interface SecretReentryRequest {
    key: string
    retry: SecretReentryRetry
}

export interface SecretReentryPrompt {
    key: string
    label: string
    // The masked entries of a dictionary secret, each of which has to be typed again. Null for a single value.
    entryKeys: string[] | null
}

/** The input key the API refused to send to a new address until its secret is entered again. */
export function secretReentryKey(error: unknown): string | null {
    const data = (error as { data?: { code?: unknown; attr?: unknown } } | null)?.data
    if (data?.code !== 'secret_reentry_required' || typeof data.attr !== 'string') {
        return null
    }
    return data.attr.startsWith('inputs__') ? data.attr.slice('inputs__'.length) : null
}

