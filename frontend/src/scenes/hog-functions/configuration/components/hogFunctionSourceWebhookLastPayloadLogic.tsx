export const hogFunctionSourceWebhookLastPayloadLogic = kea<hogFunctionSourceWebhookLastPayloadLogicType>([
    props({} as HogFunctionSourceWebhookLastPayloadLogicProps),
    key(({ id }) => id),
    path((id) => ['scenes', 'pipeline', 'hogfunctions', 'hogFunctionSourceWebhookLastPayloadLogic', id]),
    loaders(({ props }) => ({
        lastPayload: [
            null as HogFunctionSourceWebhookLastPayload | null,
            {
                loadLastPayload: async () => {
                    // The time bound keeps the query off old log_entries partitions, which are tiered to object storage.
                    const query = hogql`
                        SELECT timestamp, message
                        FROM log_entries
                        WHERE log_source = 'hog_function'
                          AND log_source_id = ${props.id}
                          AND timestamp >= now() - INTERVAL 7 DAY
                          AND message LIKE 'Incoming request:%'
                        ORDER BY timestamp DESC
                        LIMIT 1
                    `
                    const response = await api.queryHogQL(
                        query,
                        { scene: 'HogFunction', productKey: 'pipeline_destinations' },
                        { refresh: 'force_blocking' }
                    )
                    const row = response.results?.[0] as [string, string] | undefined
                    if (!row) {
                        return null
                    }
                    return { timestamp: row[0], payload: parseIncomingRequestLogMessage(row[1]) }
                },
            },
        ],
    })),
    listeners(() => ({
        loadLastPayloadSuccess: ({ lastPayload }) => {
            posthog.capture('hog function source webhook last payload viewed', {
                has_payload: !!lastPayload,
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadLastPayload()
    }),
])
