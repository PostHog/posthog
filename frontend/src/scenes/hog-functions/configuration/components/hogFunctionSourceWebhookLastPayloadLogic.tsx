// The webhook template logs the body with `print('Incoming request:', request.body)`, and print joins its args with ", ".
const INCOMING_REQUEST_PREFIX = /^Incoming request:,?\s*/

export function parseIncomingRequestLogMessage(message: string): string {
    const raw = message.replace(INCOMING_REQUEST_PREFIX, '')
    try {
        return JSON.stringify(JSON.parse(raw), null, 2)
    } catch {
        return raw
    }
}

