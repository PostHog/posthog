/**
 * The staged-draft lifecycle of an existing function: review, publish, discard. Agents (MCP) stage
 * config edits to an enabled destination as a draft instead of changing it live, and this is where a
 * person promotes or throws away that draft.
 */
export const hogFunctionDraftLogic = kea<hogFunctionDraftLogicType>([
    path((key) => ['scenes', 'hog-functions', 'configuration', 'hogFunctionDraftLogic', key]),
    props({} as HogFunctionConfigurationLogicProps),
    key(({ id, logicKey }) => (logicKey ? `${logicKey}_${id ?? 'new'}` : (id ?? 'new'))),
    connect((props: HogFunctionConfigurationLogicProps) => ({
        values: [
            teamLogic,
            ['currentTeamIdStrict'],
            hogFunctionConfigurationLogic(props),
            ['hogFunction', 'configurationChanged', 'type'],
        ],
        actions: [hogFunctionConfigurationLogic(props), ['loadHogFunction']],
    })),
    actions({
        toggleShowDraftChanges: true,
        publishDraft: true,
        confirmPublishDraft: (confirmToken: string) => ({ confirmToken }),
        discardDraft: true,
        confirmDiscardDraft: true,
        setDraftActionPending: (pending: HogFunctionDraftAction | null) => ({ pending }),
    }),
    reducers({
        showDraftChanges: [
            false,
            {
                toggleShowDraftChanges: (state) => !state,
            },
        ],
        // Drives the buttons' loading and disabled state, so publish and discard can't race each other
        // or double-submit.
        draftActionPending: [
            null as HogFunctionDraftAction | null,
            {
                setDraftActionPending: (_, { pending }) => pending,
            },
        ],
    }),
    selectors({
        hasStagedDraft: [
            (s) => [s.hogFunction],
            (hogFunction: HogFunctionType | null): boolean => !!hogFunction?.draft,
        ],
        draftDiffs: [
            (s) => [s.hogFunction],
            (hogFunction: HogFunctionType | null): HogFunctionFieldDiff[] =>
                hogFunction?.draft ? buildHogFunctionDraftDiff(hogFunction, hogFunction.draft) : [],
        ],
        draftActionDisabledReason: [
            (s) => [s.configurationChanged, s.draftActionPending],
            (configurationChanged: boolean, draftActionPending: HogFunctionDraftAction | null): string | undefined =>
                // Publish and discard reload the function, and the reload resets the form.
                configurationChanged
                    ? 'Save or clear your edits first'
                    : draftActionPending
                      ? 'Another draft action is in progress'
                      : undefined,
        ],
    }),
    listeners(({ actions, values }) => ({
        toggleShowDraftChanges: () => {
            if (values.showDraftChanges) {
                // pinned: analytics event name
                posthog.capture('hog function draft changes viewed', { type: values.type })
            }
        },
        publishDraft: async () => {
            const id = values.hogFunction?.id
            if (!id || values.draftActionPending) {
                return
            }
            actions.setDraftActionPending('publish')
            let preview: HogFunctionPublishResponseApi
            try {
                // Two-step publish: the unconfirmed call only previews what changes and mints the token
                // a confirmed publish must return, so a draft that moved since can't go live blind.
                preview = await hogFunctionsPublishCreate(String(values.currentTeamIdStrict), id, { confirm: false })
            } catch {
                lemonToast.error('Could not load the publish preview. Try again.')
                return
            } finally {
                actions.setDraftActionPending(null)
            }
            const changedFields = preview.changed_fields ?? []
            openHogFunctionPublishDraftDialog({
                diffs: values.draftDiffs.filter((diff) => changedFields.includes(diff.field)),
                changedFields,
                enabled: !!values.hogFunction?.enabled,
                onConfirm: () => actions.confirmPublishDraft(preview.confirm_token ?? ''),
            })
        },
        confirmPublishDraft: async ({ confirmToken }) => {
            const id = values.hogFunction?.id
            // draftActionPending also guards the dialog's close animation, where a fast double-click
            // on the confirm button dispatches twice.
            if (!id || values.draftActionPending) {
                return
            }
            actions.setDraftActionPending('publish')
            try {
                await hogFunctionsPublishCreate(String(values.currentTeamIdStrict), id, {
                    confirm: true,
                    confirm_token: confirmToken,
                })
                lemonToast.success('Changes published')
                // pinned: analytics event name
                posthog.capture('hog function draft published', { type: values.type })
            } catch (error) {
                lemonToast.error(
                    error instanceof ApiError && error.status !== 409 && error.detail
                        ? error.detail
                        : 'Publishing failed. Review the staged changes and try again.'
                )
            } finally {
                actions.setDraftActionPending(null)
                actions.loadHogFunction()
            }
        },
        discardDraft: () => {
            if (values.draftActionPending) {
                return
            }
            LemonDialog.open({
                title: 'Discard staged changes?',
                description: 'This deletes the staged changes. The live version does not change.',
                primaryButton: {
                    children: 'Discard',
                    status: 'danger',
                    onClick: () => actions.confirmDiscardDraft(),
                    'data-attr': 'hog-function-draft-discard-confirm',
                },
                secondaryButton: {
                    children: 'Cancel',
                },
            })
        },
        confirmDiscardDraft: async () => {
            const id = values.hogFunction?.id
            if (!id || values.draftActionPending) {
                return
            }
            actions.setDraftActionPending('discard')
            try {
                await hogFunctionsDiscardDraftCreate(String(values.currentTeamIdStrict), id)
                lemonToast.success('Staged changes discarded')
                // pinned: analytics event name
                posthog.capture('hog function draft discarded', { type: values.type })
            } catch {
                lemonToast.error('Could not discard the staged changes. Try again.')
            } finally {
                actions.setDraftActionPending(null)
                actions.loadHogFunction()
            }
        },
    })),
])
