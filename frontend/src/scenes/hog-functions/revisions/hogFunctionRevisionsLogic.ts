export const hogFunctionRevisionsLogic = kea<hogFunctionRevisionsLogicType>([
    path((key) => ['scenes', 'hog-functions', 'revisions', 'hogFunctionRevisionsLogic', key]),
    props({} as HogFunctionRevisionsLogicProps),
    key(({ id }) => id),
    connect(({ id }: HogFunctionRevisionsLogicProps) => ({
        values: [
            teamLogic,
            ['currentTeamIdStrict'],
            hogFunctionConfigurationLogic({ id }),
            ['hogFunction', 'configurationChanged'],
        ],
        actions: [hogFunctionConfigurationLogic({ id }), ['loadHogFunction', 'loadHogFunctionSuccess']],
    })),
    actions({
        restoreRevision: (version: number) => ({ version }),
        confirmRestoreRevision: (version: number, expectedDraftUpdatedAt: string | null) => ({
            version,
            expectedDraftUpdatedAt,
        }),
        setRestoringVersion: (version: number | null) => ({ version }),
    }),
    reducers({
        restoringVersion: [
            null as number | null,
            {
                setRestoringVersion: (_, { version }) => version,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        revisionsResponse: [
            null as PaginatedHogFunctionRevisionBasicListApi | null,
            {
                loadRevisions: async () => {
                    return await hogFunctionsRevisionsList(String(values.currentTeamIdStrict), props.id)
                },
            },
        ],
    })),
    selectors({
        revisions: [
            (s) => [s.revisionsResponse],
            (response: PaginatedHogFunctionRevisionBasicListApi | null): HogFunctionRevisionBasicApi[] =>
                response?.results ?? [],
        ],
        revisionsCount: [
            (s) => [s.revisionsResponse],
            (response: PaginatedHogFunctionRevisionBasicListApi | null): number => response?.count ?? 0,
        ],
        liveVersion: [(s) => [s.hogFunction], (hogFunction: HogFunctionType | null) => hogFunction?.version ?? null],
        restoreDisabledReason: [
            (s) => [s.configurationChanged, s.restoringVersion],
            (configurationChanged: boolean, restoringVersion: number | null): string | undefined =>
                // A restore reloads the function, and the reload resets the configuration form.
                configurationChanged
                    ? 'Save or clear your edits first'
                    : restoringVersion !== null
                      ? 'Another restore is in progress'
                      : undefined,
        ],
    }),
    listeners(({ actions, props, values }) => ({
        restoreRevision: ({ version }) => {
            if (values.restoringVersion !== null) {
                return
            }
            // The stamp of the draft this confirmation is about. The restore sends it as a fence, so a
            // draft staged or edited after this dialog opened returns 409 instead of being replaced.
            const expectedDraftUpdatedAt = values.hogFunction?.draft
                ? (values.hogFunction.draft_updated_at ?? null)
                : null
            LemonDialog.open({
                title: `Restore version ${version} as draft?`,
                description: values.hogFunction?.draft
                    ? 'This replaces your current staged draft with this version. The live destination keeps running until you publish.'
                    : 'This version opens as a draft. The live destination keeps running until you publish.',
                primaryButton: {
                    children: 'Restore as draft',
                    onClick: () => actions.confirmRestoreRevision(version, expectedDraftUpdatedAt),
                    'data-attr': 'hog-function-revision-restore-confirm',
                },
                secondaryButton: {
                    children: 'Cancel',
                },
            })
        },
        confirmRestoreRevision: async ({ version, expectedDraftUpdatedAt }, breakpoint) => {
            if (values.restoringVersion !== null) {
                return
            }
            actions.setRestoringVersion(version)
            try {
                // Without a draft at confirm time there is nothing to overwrite, so a draft staged since
                // returns 409 instead of being silently replaced.
                const hogFunction = await hogFunctionsRevisionsRestoreCreate(
                    String(values.currentTeamIdStrict),
                    props.id,
                    version,
                    { overwrite: expectedDraftUpdatedAt !== null, expected_draft_updated_at: expectedDraftUpdatedAt }
                )
                breakpoint()
                lemonToast.success(`Version ${version} restored as draft`)
                // pinned: analytics event name
                posthog.capture('hog function revision restored', { type: hogFunction.type })
                actions.loadHogFunctionSuccess(hogFunction as unknown as HogFunctionType)
                router.actions.push(urls.hogFunction(props.id, 'configuration'))
            } catch (error) {
                if (error instanceof ApiError && error.status === 409) {
                    lemonToast.error('The staged draft changed while you were confirming. Review it and try again.')
                    actions.loadHogFunction()
                } else if (error instanceof ApiError) {
                    lemonToast.error('Could not restore this version. Try again.')
                } else {
                    throw error
                }
            } finally {
                actions.setRestoringVersion(null)
            }
        },
    })),
    subscriptions(({ actions }) => ({
        // A publish or a restore from another tab or from PostHog AI moves the live version.
        hogFunction: (hogFunction: HogFunctionType | null, previous: HogFunctionType | null | undefined) => {
            if (previous !== undefined && hogFunction?.version !== previous?.version) {
                actions.loadRevisions()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadRevisions()
    }),
])
