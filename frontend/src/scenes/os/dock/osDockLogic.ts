/**
 * The dock on the OS page: the App Store and the open windows. It also answers the App Store
 * window's messages, because the store runs in its own frame.
 */
export const osDockLogic = kea<osDockLogicType>([
    path(['scenes', 'os', 'dock', 'osDockLogic']),
    connect(() => ({
        values: [osInstalledAppsLogic, ['catalogApps'], osWindowsLogic, ['windows', 'focusedWindow']],
        actions: [
            osWindowsLogic,
            ['focusWindow', 'minimizeWindow', 'restoreWindow'],
            osShellLogic,
            ['openApp'],
            osInstalledAppsLogic,
            ['loadCustomProducts'],
        ],
    })),
    actions({
        activateWindow: (id: string) => ({ id }),
        openAppStore: (origin?: OsPoint) => ({ origin }),
        openStoreApp: (key: string) => ({ key }),
    }),
    selectors({
        knownApps: [(s) => [s.catalogApps], (catalogApps: OsApp[]): OsApp[] => [...OS_SYSTEM_APPS, ...catalogApps]],
        dock: [
            (s) => [s.windows, s.focusedWindow, s.knownApps],
            (windows: OsWindowState[], focusedWindow: OsWindowState | null, knownApps: OsApp[]): OsDockItems =>
                osDockItems(windows, focusedWindow?.id ?? null, knownApps),
        ],
    }),
    listeners(({ actions, values }) => ({
        activateWindow: ({ id }) => {
            const target = values.windows.find((w) => w.id === id)
            if (!target) {
                return
            }
            const action = osDockClickAction({ focused: values.focusedWindow?.id === id, minimized: target.minimized })
            if (action === 'restore') {
                actions.restoreWindow(id)
            } else if (action === 'focus') {
                actions.focusWindow(id)
            } else {
                actions.minimizeWindow(id)
            }
        },
        openAppStore: ({ origin }) => {
            const { windowId } = values.dock.store
            if (windowId) {
                actions.activateWindow(windowId)
            } else {
                actions.openApp(urls.osAppStore(), 'App Store', origin)
            }
        },
        openStoreApp: ({ key }) => {
            const app = values.knownApps.find((known) => known.key === key)
            if (app?.href) {
                actions.openApp(app.href, app.name)
            }
        },
    })),
    afterMount(({ actions, cache }) => {
        cache.disposables.add(
            () => {
                const onMessage = (event: MessageEvent): void => {
                    const message = readOsStoreMessage(event)
                    if (message?.type === 'posthog-os-store:installed-changed') {
                        actions.loadCustomProducts()
                    } else if (message?.type === 'posthog-os-store:open-app') {
                        actions.openStoreApp(message.key)
                    }
                }
                window.addEventListener('message', onMessage)
                return () => window.removeEventListener('message', onMessage)
            },
            'osStoreMessages',
            { pauseOnPageHidden: false }
        )
    }),
])
