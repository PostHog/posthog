import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router, urlToAction } from 'kea-router'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { urls } from 'scenes/urls'

import { OsApp, OsStoreSection } from './osAppCatalog'
import { osInstalledAppsLogic } from './osInstalledAppsLogic'
import { osStoreOpenApp, osStorePreviewApp, postToOs } from './osStoreMessages'

function matches(app: OsApp, query: string): boolean {
    return `${app.name} ${app.description ?? ''}`.toLowerCase().includes(query)
}

