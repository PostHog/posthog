/** The App Store window: the front page at `/app-store`, and one listing per app at `/app-store/<slug>`. */
export const osAppStoreSceneLogic = kea<osAppStoreSceneLogicType>([
    path(['scenes', 'os', 'store', 'osAppStoreSceneLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            osInstalledAppsLogic,
            ['catalogApps', 'storeSections', 'installedKeys', 'pendingChanges'],
        ],
        actions: [osInstalledAppsLogic, ['installApp', 'removeApp', 'loadCustomProducts']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setSelectedSlug: (slug: string | null) => ({ slug }),
        openApp: (app: OsApp) => ({ app }),
        previewApp: (app: OsApp) => ({ app }),
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        selectedSlug: [null as string | null, { setSelectedSlug: (_, { slug }) => slug }],
    }),
    selectors({
        visibleSections: [
            (s) => [s.storeSections, s.search],
            (storeSections: OsStoreSection[], search: string): OsStoreSection[] => {
                const query = search.trim().toLowerCase()
                if (!query) {
                    return storeSections
                }
                return storeSections
                    .map((section) => ({ ...section, apps: section.apps.filter((app) => matches(app, query)) }))
                    .filter((section) => section.apps.length > 0)
            },
        ],
        /** The app on the listing page. Null on the front page, and for an app this user cannot see. */
        selectedApp: [
            (s) => [s.catalogApps, s.selectedSlug],
            (catalogApps: OsApp[], selectedSlug: string | null): OsApp | null =>
                catalogApps.find((app) => app.slug === selectedSlug) ?? null,
        ],
    }),
    listeners(() => ({
        openApp: ({ app }) => {
            // In an OS window the OS opens the app in a window of its own, so the store stays open.
            if (!postToOs(osStoreOpenApp(app.key))) {
                router.actions.push(app.href)
            }
        },
        previewApp: ({ app }) => {
            postToOs(osStorePreviewApp(app.key))
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.osAppStore()]: () => {
            if (values.selectedSlug !== null) {
                actions.setSelectedSlug(null)
            }
        },
        [urls.osAppStore(':app')]: ({ app }) => {
            if (values.selectedSlug !== (app ?? null)) {
                actions.setSelectedSlug(app ?? null)
            }
        },
    })),
    afterMount(({ actions, values, cache }) => {
        // With the flag off the scene shows the not-found page, so it has nothing to load.
        if (!values.featureFlags[FEATURE_FLAGS.OS_SHELL]) {
            return
        }
        // Other windows (Settings, another App Store window) can change the installed apps, so the
        // store reloads them when it opens and each time the user comes back to its window.
        actions.loadCustomProducts()
        cache.disposables.add(
            () => {
                const onFocus = (): void => actions.loadCustomProducts()
                window.addEventListener('focus', onFocus)
                return () => window.removeEventListener('focus', onFocus)
            },
            'reloadAppsOnFocus',
            { pauseOnPageHidden: false }
        )
    }),
])
