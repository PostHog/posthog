/**
 * The installed apps: the system apps plus the user's `UserProductList` rows, which also back the
 * desktop icons and the sidebar's "My tools". Install and remove write that list, so every surface
 * that reads it follows.
 */
export const osInstalledAppsLogic = kea<osInstalledAppsLogicType>([
    path(['scenes', 'os', 'store', 'osInstalledAppsLogic']),
    connect(() => ({
        values: [customProductsLogic, ['customProducts', 'customProductsLoading'], featureFlagLogic, ['featureFlags']],
        actions: [customProductsLogic, ['loadCustomProducts', 'loadCustomProductsSuccess']],
    })),
    actions({
        installApp: (key: string) => ({ key }),
        removeApp: (key: string) => ({ key }),
        appWriteSettled: (key: string, enabled: boolean, saved: boolean) => ({ key, enabled, saved }),
    }),
    reducers({
        // The value each in-flight write asks for. It wins over the loaded list until the write
        // settles, so a reload that answers with an older list cannot undo a click.
        pendingChanges: [
            {} as Record<string, boolean>,
            {
                installApp: (state, { key }) => (key.startsWith('system:') ? state : { ...state, [key]: true }),
                removeApp: (state, { key }) => (key.startsWith('system:') ? state : { ...state, [key]: false }),
                appWriteSettled: (state, { key }) => {
                    const { [key]: _settled, ...rest } = state
                    return rest
                },
            },
        ],
    }),
    selectors({
        catalogApps: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): OsApp[] =>
                osCatalogApps(
                    getDefaultTreeProducts(),
                    featureFlags,
                    (item) => (item.sceneKey && sceneConfigurations[item.sceneKey]?.description) || null
                ),
        ],
        storeSections: [
            (s) => [s.catalogApps],
            (catalogApps: OsApp[]): OsStoreSection[] => osStoreSections(catalogApps),
        ],
        pendingKeys: [
            (s) => [s.pendingChanges],
            (pendingChanges: Record<string, boolean>): Set<string> => new Set(Object.keys(pendingChanges)),
        ],
        installedKeys: [
            (s) => [s.customProducts, s.pendingChanges],
            (customProducts: UserProductListItem[], pendingChanges: Record<string, boolean>): Set<string> => {
                const keys = new Set(customProducts.map((item) => item.product_path))
                for (const [key, enabled] of Object.entries(pendingChanges)) {
                    if (enabled) {
                        keys.add(key)
                    } else {
                        keys.delete(key)
                    }
                }
                return keys
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const write = async (key: string, enabled: boolean): Promise<void> => {
            if (key.startsWith('system:')) {
                return
            }
            // A load that started before this write answers with the list from before it, so reload once the write settles.
            if (values.customProductsLoading) {
                cache.reloadAfterWrites = true
            }
            actions.loadCustomProductsSuccess(withProduct(values.customProducts, key, enabled))
            let saved = true
            try {
                await api.userProductList.bulkUpdate([{ product_path: key, enabled }])
            } catch {
                saved = false
            }
            actions.appWriteSettled(key, enabled, saved)
        }
        return {
            installApp: ({ key }) => write(key, true),
            removeApp: ({ key }) => write(key, false),
            loadCustomProducts: () => {
                if (values.pendingKeys.size > 0) {
                    cache.reloadAfterWrites = true
                }
            },
            appWriteSettled: ({ key, enabled, saved }) => {
                if (!saved) {
                    lemonToast.error('Could not save your apps. Try again.')
                    // Undo here too, because the reload can fail for the same reason the write did.
                    actions.loadCustomProductsSuccess(withProduct(values.customProducts, key, !enabled))
                    cache.reloadAfterWrites = true
                } else if (values.customProducts.some((item) => item.product_path === key) !== enabled) {
                    // A reload answered while this write was in flight, with the list from before it.
                    actions.loadCustomProductsSuccess(withProduct(values.customProducts, key, enabled))
                }
                postToOs(osStoreInstalledChanged())
                if (values.pendingKeys.size === 0 && cache.reloadAfterWrites) {
                    cache.reloadAfterWrites = false
                    actions.loadCustomProducts()
                }
            },
        }
    }),
])
