function withProduct(list: UserProductListItem[], productPath: string, enabled: boolean): UserProductListItem[] {
    const without = list.filter((item) => item.product_path !== productPath)
    if (!enabled) {
        return without
    }
    // Every consumer reads `product_path` only, so the fields the server fills in stay placeholders.
    const now = new Date().toISOString()
    return [...without, { id: '', product_path: productPath, enabled: true, created_at: now, updated_at: now }]
}

