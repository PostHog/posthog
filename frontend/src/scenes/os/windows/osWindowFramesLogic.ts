/** Decides when each window's frame goes into the page, and tracks whether the app in it has loaded. */
export const osWindowFramesLogic = kea<osWindowFramesLogicType>([
    path(['scenes', 'os', 'windows', 'osWindowFramesLogic']),
    connect(() => ({
        values: [osWindowsLogic, ['windows']],
        actions: [
            osWindowsLogic,
            ['windowNavigated', 'openWindow', 'restoreLayout', 'restoreWindow', 'focusWindow', 'closeWindow'],
        ],
    })),
    actions({
        framesAdmitted: (ids: string[]) => ({ ids }),
        frameSlow: (id: string) => ({ id }),
        reloadFrame: (id: string) => ({ id }),
        /** The frame loaded a page that is not the app, such as a server error page or another site. */
        framePageLoaded: (id: string) => ({ id }),
    }),
    reducers({
        frames: [
            {} as Record<string, OsFrame>,
            {
                framesAdmitted: (frames, { ids }) => ({
                    ...frames,
                    ...Object.fromEntries(ids.map((id): [string, OsFrame] => [id, { status: 'loading', attempt: 0 }])),
                }),
                // The framed app reports its page only once its page shell runs, so its first report means it loaded.
                windowNavigated: (frames, { id }) => markReady(frames, id),
                // Such a page never sends a report, and the cover would hide it.
                framePageLoaded: (frames, { id }) => markReady(frames, id),
                frameSlow: (frames, { id }) =>
                    frames[id]?.status === 'loading' ? { ...frames, [id]: { ...frames[id], status: 'slow' } } : frames,
                reloadFrame: (frames, { id }) =>
                    frames[id] ? { ...frames, [id]: { status: 'loading', attempt: frames[id].attempt + 1 } } : frames,
                closeWindow: (frames, { id }) => {
                    const { [id]: _closed, ...rest } = frames
                    return rest
                },
            },
        ],
    }),
    selectors({
        frameStatus: [
            (s) => [s.windows, s.frames],
            (windows: OsWindowState[], frames: Record<string, OsFrame>): Record<string, OsFrameStatus> =>
                Object.fromEntries(windows.map((w) => [w.id, frames[w.id]?.status ?? 'queued'])),
        ],
        frameAttempts: [
            (s) => [s.frames],
            (frames: Record<string, OsFrame>): Record<string, number> =>
                Object.fromEntries(Object.entries(frames).map(([id, frame]) => [id, frame.attempt])),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        cache.admit = (): void => {
            const ids = framesToAdmit(values.windows, values.frames)
            if (ids.length) {
                actions.framesAdmitted(ids)
            }
        }
        const watchLoad = (id: string): void => {
            cache.disposables.add(() => {
                const timeout = window.setTimeout(() => actions.frameSlow(id), OS_FRAME_SLOW_MS)
                return () => window.clearTimeout(timeout)
            }, `slow:${id}`)
        }
        return {
            framesAdmitted: ({ ids }) => ids.forEach(watchLoad),
            framePageLoaded: ({ id }) => {
                cache.disposables.dispose(`slow:${id}`)
                cache.admit()
            },
            reloadFrame: ({ id }) => watchLoad(id),
            frameSlow: () => cache.admit(),
            openWindow: () => cache.admit(),
            restoreLayout: () => cache.admit(),
            // Both un-minimize a window.
            restoreWindow: () => cache.admit(),
            focusWindow: () => cache.admit(),
            closeWindow: ({ id }) => {
                cache.disposables.dispose(`slow:${id}`)
                cache.admit()
            },
            windowNavigated: ({ id }) => {
                cache.disposables.dispose(`slow:${id}`)
                cache.admit()
            },
        }
    }),
    afterMount(({ cache }) => {
        cache.admit()
    }),
])
