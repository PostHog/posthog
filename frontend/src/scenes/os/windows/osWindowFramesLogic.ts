import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { OsWindowState, osWindowsLogic } from './osWindowsLogic'

/**
 * - `queued`: the window waits for its turn, so its frame is not in the page yet.
 * - `loading`: the frame loads the app, and the app has not reported a page yet.
 * - `ready`: the app in the frame reported its first page through the bridge.
 * - `slow`: the frame still loads after a long time.
 */
export type OsFrameStatus = 'queued' | 'loading' | 'ready' | 'slow'

interface OsFrame {
    status: Exclude<OsFrameStatus, 'queued'>
    /** Goes up on each reload, so the window can load its frame again. */
    attempt: number
}

/**
 * Frames share the page's main thread and the web server. When every window boots at once, the top window
 * waits for all of them, so the top windows boot first.
 */
export const OS_FRAME_BOOT_LIMIT = 2

/** After this long, a window offers to reload its frame, and the frame stops holding up the windows behind it. */
export const OS_FRAME_SLOW_MS = 20_000

/**
 * The windows whose frames can go into the page now. The top visible window always gets its frame, because
 * the person looks at it. The windows behind it follow from the top down, while fewer than
 * `OS_FRAME_BOOT_LIMIT` frames load. A minimized window waits until it is restored.
 * A frame that is in the page stays there, so minimizing or covering a window keeps its app as it was.
 */
function framesToAdmit(windows: OsWindowState[], frames: Record<string, OsFrame>): string[] {
    let loading = Object.values(frames).filter((frame) => frame.status === 'loading').length
    const admitted: string[] = []
    const visible = windows.filter((w) => !w.minimized).sort((a, b) => b.zIndex - a.zIndex)
    visible.forEach((w, index) => {
        if (!frames[w.id] && (index === 0 || loading < OS_FRAME_BOOT_LIMIT)) {
            admitted.push(w.id)
            loading++
        }
    })
    return admitted
}

function markReady(frames: Record<string, OsFrame>, id: string): Record<string, OsFrame> {
    return frames[id] && frames[id].status !== 'ready'
        ? { ...frames, [id]: { ...frames[id], status: 'ready' } }
        : frames
}

/** True when the frame shows the app, which reports when it has loaded. Another site or a server page does not. */
export function osFrameShowsApp(frame: HTMLIFrameElement): boolean {
    try {
        return !!frame.contentDocument?.getElementById('root')
    } catch {
        return false
    }
}

