export type osFrameBridgeLogicType = MakeLogicType<osFrameBridgeLogicValues, osFrameBridgeLogicActions>

/**
 * The framed app's side of the bridge. Mount it only inside an OS window (`isOsFrame`). It reports the
 * page to the OS and hands the OS what a window cannot do itself: new windows, window shortcuts, side
 * panels, the spotlight, and pages that refuse to load in a frame.
 */
export const osFrameBridgeLogic = kea<osFrameBridgeLogicType>([
    path(['scenes', 'os', 'bridge', 'osFrameBridgeLogic']),
    connect(() => ({
        values: [commandLogic, ['isCommandOpen']],
        actions: [
            commandLogic,
            ['openCommand', 'toggleCommand', 'closeCommand'],
            sidePanelStateLogic,
            ['openSidePanel', 'closeSidePanel'],
            userLogic,
            ['loadUser', 'updateUserSuccess'],
        ],
    })),
    listeners(({ actions, values, cache }) => {
        const openSpotlight = (): void => {
            if (values.isCommandOpen) {
                actions.closeCommand()
                send({ type: 'spotlight' })
            }
        }
        return {
            [router.actionTypes.locationChanged]: ({ method }) => cache.reportLocation(method === 'POP'),
            openSidePanel: ({ tab, options }) => {
                // Support falls back to a form inside the window, so only the other panels go to the OS.
                if (tab === SidePanelTab.Support) {
                    return
                }
                actions.closeSidePanel()
                if (osSidePanelPath(tab, options)) {
                    send({ type: 'side-panel', tab, ...(options ? { options } : {}) })
                } else {
                    // The side panel's hash sync can open the same panel twice in a row, so one toast id keeps one toast.
                    lemonToast.info('This panel is not available in windows yet.', {
                        toastId: 'os-side-panel-unavailable',
                    })
                }
            },
            openCommand: openSpotlight,
            toggleCommand: openSpotlight,
            updateUserSuccess: () => send({ type: 'user-changed' }),
        }
    }),
    afterMount(({ actions, cache }) => {
        let lastReport: string | null = null
        cache.reportLocation = (traversed: boolean): void => {
            const { pathname, search, hash } = router.values.location
            const report: OsBridgeMessage = {
                type: 'location',
                path: `${pathname}${search}${hash}`,
                title: windowTitleFromDocumentTitle(document.title),
                traversed,
            }
            const key = `${report.path}\n${report.title}`
            // A back or forward always goes out, because it brings the window to the front.
            if (key !== lastReport || traversed) {
                lastReport = key
                send(report)
            }
        }
        setOsWindowOpener((path) => send({ type: 'open-window', path }))
        cache.reportLocation(false)

        cache.disposables.add(
            () => {
                const onNewWindowClick = (event: MouseEvent): void => {
                    const target = linkTargetFor(event)
                    if (target?.kind === 'new-window') {
                        event.preventDefault()
                        send({ type: 'open-window', path: target.path })
                    }
                }
                // Runs after the app's own handlers, so a click the app already handled stays handled.
                const onLeavingClick = (event: MouseEvent): void => {
                    const target = event.defaultPrevented ? null : linkTargetFor(event)
                    if (target?.kind === 'new-tab') {
                        event.preventDefault()
                        window.open(target.url, '_blank', 'noopener,noreferrer')
                    } else if (target?.kind === 'top') {
                        event.preventDefault()
                        send({ type: 'open-top', url: target.url })
                    }
                }
                const onKeyDown = (event: KeyboardEvent): void => {
                    const command = osWindowCommandFor(event)
                    if (command) {
                        event.preventDefault()
                        event.stopPropagation()
                        send({ type: 'window-command', command })
                    }
                }
                const onPointerDown = (): void => send({ type: 'focus' })
                const onHostMessage = (event: MessageEvent): void => {
                    if (isFromOsHost(event, window) && parseOsHostMessage(event.data)?.type === 'user-changed') {
                        actions.loadUser()
                    }
                }
                const onTitleChange = (): void => cache.reportLocation(false)

                // The app's link handlers stop propagation on a Cmd+click, so new windows are caught while capturing.
                window.addEventListener('click', onNewWindowClick, true)
                window.addEventListener('auxclick', onNewWindowClick, true)
                window.addEventListener('click', onLeavingClick)
                window.addEventListener('keydown', onKeyDown, true)
                window.addEventListener('pointerdown', onPointerDown, true)
                window.addEventListener('message', onHostMessage)

                // Only the head's direct children and the title are watched, because the app adds styles to the head all the time.
                const titleObserver = new MutationObserver(onTitleChange)
                titleObserver.observe(document.head, { childList: true })
                const title = document.head.querySelector('title')
                if (title) {
                    titleObserver.observe(title, { childList: true, characterData: true, subtree: true })
                }

                // A redirect in code or a form post never passes a link, so the Navigation API catches the
                // page loads that must leave the frame. Browsers without it load those pages in the window.
                const navigation = (window as Window & { navigation?: EventTarget }).navigation
                const onNavigate = (event: Event): void => {
                    const navigateEvent = event as Event & {
                        destination: { url: string }
                        downloadRequest: string | null
                    }
                    if (!navigateEvent.cancelable || navigateEvent.downloadRequest !== null) {
                        return
                    }
                    const url = osNavigationTarget(navigateEvent.destination.url, window.location.origin)
                    if (url) {
                        navigateEvent.preventDefault()
                        send({ type: 'open-top', url })
                    }
                }
                navigation?.addEventListener('navigate', onNavigate)

                return () => {
                    window.removeEventListener('click', onNewWindowClick, true)
                    window.removeEventListener('auxclick', onNewWindowClick, true)
                    window.removeEventListener('click', onLeavingClick)
                    window.removeEventListener('keydown', onKeyDown, true)
                    window.removeEventListener('pointerdown', onPointerDown, true)
                    window.removeEventListener('message', onHostMessage)
                    titleObserver.disconnect()
                    navigation?.removeEventListener('navigate', onNavigate)
                }
            },
            'bridge',
            { pauseOnPageHidden: false }
        )
    }),
    beforeUnmount(() => {
        setOsWindowOpener(null)
    }),
])
