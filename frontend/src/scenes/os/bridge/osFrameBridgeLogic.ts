/**
 * The app titles pages "Page • Section • PostHog", and a window shows only the page part. A loading app
 * has the bare "PostHog" title, which gives an empty string, so the window keeps the title it had.
 */
export function windowTitleFromDocumentTitle(documentTitle: string): string {
    const parts = documentTitle.split(' • ')
    return parts.length > 1 ? parts[0].trim() : ''
}

function linkIn(event: MouseEvent): HTMLAnchorElement | null {
    // `composedPath` also finds a link inside a shadow root, where `event.target` is the host.
    for (const element of event.composedPath()) {
        if (element instanceof HTMLAnchorElement && element.hasAttribute('href')) {
            return element
        }
    }
    return null
}

function linkTargetFor(event: MouseEvent): OsLinkTarget | null {
    const link = linkIn(event)
    if (!link) {
        return null
    }
    return osLinkTarget(
        {
            href: link.getAttribute('href') ?? '',
            target: link.target,
            download: link.hasAttribute('download'),
            button: event.button,
            metaKey: event.metaKey,
            ctrlKey: event.ctrlKey,
            shiftKey: event.shiftKey,
            altKey: event.altKey,
        },
        window.location.href
    )
}

function send(message: OsBridgeMessage): void {
    postToOs(window, message)
}

