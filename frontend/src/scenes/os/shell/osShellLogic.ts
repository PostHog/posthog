import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { FlatNavProductGroup, flatNavLogic } from '~/layout/panel-layout/navbar/tabs/flat-nav/flatNavLogic'
import { customProductsLogic } from '~/layout/panel-layout/ProjectTree/customProductsLogic'

import type { OsPoint } from '../windows/osWindowGeometry'
import { osWindowsLogic } from '../windows/osWindowsLogic'
import { osAppSrc } from './osAppSrc'
import { OsDesktopColumns, osDesktopColumns } from './osDesktopApps'
import { OsWallpaperKey, OsWallpaperOption, resolveOsWallpaper } from './osWallpapers'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface osShellLogicValues {
    productGroups: FlatNavProductGroup[] // flatNavLogic
    desktopColumns: OsDesktopColumns
    storedWallpaper: string | null
    wallpaper: OsWallpaperOption
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface osShellLogicActions {
    loadCustomProducts: () => any // customProductsLogic
    openWindow: (
        path: string,
        options?: import('../windows/osWindowsLogic').OsOpenWindowOptions | undefined
    ) => {
        id: string
        options: import('../windows/osWindowsLogic').OsOpenWindowOptions
        path: string
    } // osWindowsLogic
    openApp: (
        href: string,
        title: string,
        origin?: OsPoint
    ) => {
        href: string
        origin: OsPoint | undefined
        title: string
    }
    setWallpaper: (wallpaper: OsWallpaperKey) => {
        wallpaper: OsWallpaperKey
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface osShellLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        wallpaper: (storedWallpaper: any) => OsWallpaperOption
        desktopColumns: (productGroups: any) => OsDesktopColumns
    }
}

export type osShellLogicType = MakeLogicType<
    osShellLogicValues,
    osShellLogicActions,
    Record<string, any>,
    osShellLogicMeta
>

export const osShellLogic = kea<osShellLogicType>([
    path(['scenes', 'os', 'shell', 'osShellLogic']),
    connect(() => ({
        values: [flatNavLogic, ['productGroups']],
        actions: [customProductsLogic, ['loadCustomProducts'], osWindowsLogic, ['openWindow']],
    })),
    actions({
        setWallpaper: (wallpaper: OsWallpaperKey) => ({ wallpaper }),
        openApp: (href: string, title: string, origin?: OsPoint) => ({ href, title, origin }),
    }),
    reducers({
        // Holds whatever was saved, so a wallpaper that no longer exists still resolves to a real one.
        storedWallpaper: [
            null as string | null,
            { persist: true },
            {
                setWallpaper: (_, { wallpaper }) => wallpaper,
            },
        ],
    }),
    selectors({
        wallpaper: [
            (s) => [s.storedWallpaper],
            (storedWallpaper: string | null): OsWallpaperOption => resolveOsWallpaper(storedWallpaper),
        ],
        desktopColumns: [
            (s) => [s.productGroups],
            (productGroups: FlatNavProductGroup[]): OsDesktopColumns => osDesktopColumns(productGroups),
        ],
    }),
    listeners(({ actions }) => ({
        openApp: ({ href, title, origin }) => {
            // Links that leave this origin or do not parse never reach a window frame.
            const src = osAppSrc(href, window.location.origin)
            if (src) {
                actions.openWindow(src, { title, origin })
            }
        },
    })),
    afterMount(({ actions, cache }) => {
        // Settings in a window can change the picked tools, so the desktop reloads them when the
        // user comes back to it.
        cache.disposables.add(
            () => {
                const onFocus = (): void => actions.loadCustomProducts()
                window.addEventListener('focus', onFocus)
                return () => window.removeEventListener('focus', onFocus)
            },
            'reloadToolsOnFocus',
            { pauseOnPageHidden: false }
        )
    }),
])
