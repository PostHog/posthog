export type todayDrawersLogicType = MakeLogicType<
    todayDrawersLogicValues,
    todayDrawersLogicActions,
    Record<string, any>,
    todayDrawersLogicMeta
>

export const todayDrawersLogic = kea<todayDrawersLogicType>([
    path(['scenes', 'project-homepage', 'today', 'todayDrawersLogic']),
    connect(() => ({ actions: [todayLogic, ['setRoute']] })),
    actions({
        openEvidence: (story: TodayStory, evidenceIndex: number) => ({ story, evidenceIndex }),
        drill: (name: string) => ({ name }),
        closeTopDrawer: true,
        closeAllDrawers: true,
        copyDrawer: (drawer: TodayDrawer) => ({ drawer }),
        clearCopied: true,
    }),
    reducers({
        drawers: [
            [] as TodayDrawer[],
            {
                openEvidence: (_, { story, evidenceIndex }) => {
                    const drawer = evidenceDrawer(story, evidenceIndex)
                    return drawer ? [drawer] : []
                },
                drill: (state, { name }) => {
                    const parent = state[state.length - 1]
                    return parent && parent.depth < MAX_DRAWER_DEPTH ? [...state, childDrawer(parent, name)] : state
                },
                closeTopDrawer: (state) => state.slice(0, -1),
                closeAllDrawers: () => [],
                setRoute: () => [],
            },
        ],
        copiedDrawerId: [
            null as string | null,
            {
                copyDrawer: (_, { drawer }) => drawer.id,
                clearCopied: () => null,
                closeAllDrawers: () => null,
            },
        ],
    }),
    selectors({
        topDrawer: [
            (s) => [s.drawers],
            (drawers: TodayDrawer[]): TodayDrawer | null => drawers[drawers.length - 1] ?? null,
        ],
    }),
    listeners(({ actions, cache }) => ({
        copyDrawer: async ({ drawer }) => {
            await navigator.clipboard?.writeText(`${drawer.name}\n${drawer.value}\n${drawer.summary}`)
            cache.disposables.add(
                () => {
                    const timer = window.setTimeout(() => actions.clearCopied(), COPIED_MS)
                    return () => clearTimeout(timer)
                },
                'copied',
                { pauseOnPageHidden: false }
            )
        },
    })),
])
