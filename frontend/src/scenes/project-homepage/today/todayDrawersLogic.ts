import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { todayLogic } from './todayLogic'
import { TodayEvidenceKind, TodayStory } from './todayTypes'

export const MAX_DRAWER_DEPTH = 2
const COPIED_MS = 1800

export interface TodayDrawer {
    id: string
    depth: number
    storyTitle: string
    kind: TodayEvidenceKind
    color: string
    name: string
    value: string
    summary: string
    kicker: string
    facts: { label: string; value: string }[]
}

export function evidenceDrawer(story: TodayStory, evidenceIndex: number): TodayDrawer | null {
    const evidence = story.evidence[evidenceIndex]
    if (!evidence) {
        return null
    }
    return {
        id: `${story.id}-${evidenceIndex}`,
        depth: 0,
        storyTitle: story.title,
        kind: evidence.kind,
        color: evidence.color,
        name: evidence.product,
        value: evidence.value,
        summary: evidence.detail,
        kicker: 'Evidence object',
        facts: [
            { label: 'Story', value: story.title },
            { label: 'Product', value: evidence.product },
            { label: 'Updated', value: '2 hours ago' },
        ],
    }
}

/** A closer view of one part of the parent object, keeping the parent's kind and colour. */
export function childDrawer(parent: TodayDrawer, name: string): TodayDrawer {
    return {
        id: `${parent.id}/${name}`,
        depth: parent.depth + 1,
        storyTitle: parent.storyTitle,
        kind: parent.kind,
        color: parent.color,
        name,
        value: name,
        summary: `A closer view of the evidence behind ${parent.name.toLowerCase()}.`,
        kicker: `${parent.name} · detail`,
        facts: [
            { label: 'Parent', value: parent.name },
            { label: 'Source', value: parent.kicker },
            { label: 'Depth', value: `Layer ${parent.depth + 2}` },
        ],
    }
}

