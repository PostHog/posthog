import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'
import { userLogic } from 'scenes/userLogic'

import { todaySpacesLogic } from '~/layout/today/todaySpacesLogic'
import { UserType } from '~/types'

import { FREEFORM_TEMPLATE_ID } from 'products/canvas/frontend/canvasTemplates'
import { canvasesCreate, canvasesList } from 'products/canvas/frontend/generated/api'
import { ChannelDTOApi } from 'products/tasks/frontend/generated/api.schemas'

// pinned: the Home canvas is found again by this name in the person's personal space. Renaming it starts a new canvas.
export const TODAY_HOME_CANVAS_NAME = 'Home canvas'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayHomeCanvasLogicValues {
    currentProjectId: number | string // teamLogic
    sortedSpaces: ChannelDTOApi[] // todaySpacesLogic
    spacesLoading: boolean // todaySpacesLogic
    spacesUnavailable: boolean // todaySpacesLogic
    user: UserType | null // userLogic
    homeCanvasFailed: boolean
    homeCanvasId: string | null
    homeCanvasIdLoading: boolean
    personalSpace: ChannelDTOApi | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayHomeCanvasLogicActions {
    loadSpacesSuccess: (
        sortedSpaces: ChannelDTOApi[],
        payload?: any
    ) => {
        sortedSpaces: ChannelDTOApi[]
        payload?: any
    } // todaySpacesLogic
    loadSpaces: () => any // todaySpacesLogic
    loadHomeCanvasId: () => any
    loadHomeCanvasIdFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadHomeCanvasIdSuccess: (
        homeCanvasId: string | null,
        payload?: any
    ) => {
        homeCanvasId: string | null
        payload?: any
    }
    retryHomeCanvas: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayHomeCanvasLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        personalSpace: (sortedSpaces: ChannelDTOApi[]) => ChannelDTOApi | null
    }
}

export type todayHomeCanvasLogicType = MakeLogicType<
    todayHomeCanvasLogicValues,
    todayHomeCanvasLogicActions,
    Record<string, any>,
    todayHomeCanvasLogicMeta
>

/**
 * The freeform canvas on the Today home Canvas tab. It lives in the person's personal space, so only they see it
 * unless they share it. The first open creates it; later opens find it again by name.
 */
export const todayHomeCanvasLogic = kea<todayHomeCanvasLogicType>([
    path(['scenes', 'project-homepage', 'today', 'todayHomeCanvasLogic']),
    connect(() => ({
        values: [
            teamLogic,
            ['currentProjectId'],
            todaySpacesLogic,
            ['sortedSpaces', 'spacesLoading', 'spacesUnavailable'],
            userLogic,
            ['user'],
        ],
        actions: [todaySpacesLogic, ['loadSpacesSuccess', 'loadSpaces']],
    })),
    actions({
        retryHomeCanvas: true,
    }),
    selectors({
        personalSpace: [
            (s) => [s.sortedSpaces],
            (sortedSpaces: ChannelDTOApi[]): ChannelDTOApi | null =>
                sortedSpaces.find((space) => space.system_role === 'personal') ?? null,
        ],
    }),
    loaders(({ values }) => ({
        homeCanvasId: [
            null as string | null,
            {
                loadHomeCanvasId: async () => {
                    const projectId = String(values.currentProjectId)
                    const space = values.personalSpace
                    if (!space) {
                        throw new Error('No personal space')
                    }
                    const { results } = await canvasesList(projectId, {
                        channel: space.id,
                        kind: 'freeform',
                        search: TODAY_HOME_CANVAS_NAME,
                        created_by: values.user?.uuid,
                        ordering: '-created_at',
                    })
                    const existing = results.find((canvas) => canvas.name === TODAY_HOME_CANVAS_NAME)
                    if (existing) {
                        return existing.id
                    }
                    const canvas = await canvasesCreate(projectId, {
                        channel_id: space.id,
                        name: TODAY_HOME_CANVAS_NAME,
                        template_id: FREEFORM_TEMPLATE_ID,
                    })
                    // pinned: analytics event name and properties. Renaming them breaks dashboards.
                    posthog.capture('today home canvas created', { canvas_id: canvas.id })
                    return canvas.id
                },
            },
        ],
    })),
    reducers({
        homeCanvasFailed: [
            false,
            {
                loadHomeCanvasId: () => false,
                retryHomeCanvas: () => false,
                loadHomeCanvasIdFailure: () => true,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        retryHomeCanvas: () => {
            if (values.personalSpace) {
                actions.loadHomeCanvasId()
            } else {
                actions.loadSpaces()
            }
        },
        loadSpacesSuccess: () => {
            if (
                values.personalSpace &&
                !values.homeCanvasId &&
                !values.homeCanvasIdLoading &&
                !values.homeCanvasFailed
            ) {
                actions.loadHomeCanvasId()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.personalSpace) {
            actions.loadHomeCanvasId()
        }
    }),
])
