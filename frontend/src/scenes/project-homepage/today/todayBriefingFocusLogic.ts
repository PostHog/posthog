/**
 * What the person asked their Today briefing to show more or less of, by source product.
 * Saved per person and project, so the briefing can read it. The ranking does not use it yet.
 */
export const todayBriefingFocusLogic = kea<todayBriefingFocusLogicType>([
    path(['scenes', 'project-homepage', 'today', 'todayBriefingFocusLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),
    actions({
        steerTopic: (topic: string, direction: FocusTopicDirectionEnumApi) => ({ topic, direction }),
        removeTopic: (topic: string) => ({ topic }),
        changeTopics: (topics: FocusTopicApi[], source: TodayFocusSource) => ({ topics, source }),
    }),
    loaders(({ values }) => ({
        savedTopics: [
            [] as FocusTopicApi[],
            {
                loadFocus: async (): Promise<FocusTopicApi[]> =>
                    (await todayFocusRetrieve(String(values.currentProjectId))).topics,
                saveTopics: async ({ topics }: { topics: FocusTopicApi[] }): Promise<FocusTopicApi[]> =>
                    (await todayFocusUpdate(String(values.currentProjectId), { topics })).topics,
            },
        ],
    })),
    reducers({
        // A change shows at once; the saved list replaces it when the request returns.
        topics: [
            [] as FocusTopicApi[],
            {
                changeTopics: (_, { topics }) => topics,
                loadFocusSuccess: (_, { savedTopics }) => savedTopics,
                saveTopicsSuccess: (_, { savedTopics }) => savedTopics,
            },
        ],
    }),
    selectors({
        directions: [
            (s) => [s.topics],
            (topics: FocusTopicApi[]): Record<string, FocusTopicDirectionEnumApi> =>
                Object.fromEntries(topics.map((entry) => [entry.topic, entry.direction])),
        ],
    }),
    listeners(({ actions, values }) => ({
        // A second press on the same direction takes the topic out of the focus.
        steerTopic: ({ topic, direction }) => {
            const next = values.directions[topic] === direction ? null : direction
            actions.changeTopics(withTopic(values.topics, topic, next), 'hover_card')
        },
        removeTopic: ({ topic }) => {
            actions.changeTopics(withTopic(values.topics, topic, null), 'focus_line')
        },
        changeTopics: ({ topics, source }) => {
            actions.saveTopics({ topics })
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('today briefing focus saved', {
                source,
                more_topics: topics.filter((entry) => entry.direction === 'more').map((entry) => entry.topic),
                less_topics: topics.filter((entry) => entry.direction === 'less').map((entry) => entry.topic),
                topic_count: topics.length,
                cleared: topics.length === 0,
            })
        },
        // The app shows the error; reading the saved focus again undoes the change on screen.
        saveTopicsFailure: () => {
            actions.loadFocus()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadFocus()
    }),
])
