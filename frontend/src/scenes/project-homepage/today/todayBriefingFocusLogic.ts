/** Where the person changed the focus, sent with the `today briefing focus saved` event. */
export type TodayFocusSource = 'dialog' | 'hover_card'

function withTopic(
    focus: TodayBriefingFocus,
    topic: string,
    direction: TodayFocusDirection | null
): TodayBriefingFocus {
    const { [topic]: _, ...topics } = focus.topics
    return { ...focus, topics: direction ? { ...topics, [topic]: direction } : topics }
}

