/**
 * What the person wants their Today briefing to show more or less of. A prototype of steering the briefing:
 * the focus is kept in the browser and shown on the page, and does not change the ranking yet.
 */
export const todayBriefingFocusLogic = kea<todayBriefingFocusLogicType>([
    path(['scenes', 'project-homepage', 'today', 'todayBriefingFocusLogic']),
    connect(() => ({
        values: [todayLogic, ['briefingItems', 'reports', 'now']],
    })),
    actions({
        openFocusDialog: true,
        closeFocusDialog: true,
        setDraft: (draft: TodayBriefingFocus) => ({ draft }),
        setDraftTopic: (topic: string, direction: TodayFocusDirection | null) => ({ topic, direction }),
        setDraftDuration: (duration: TodayFocusDuration) => ({ duration }),
        saveFocus: true,
        clearFocus: true,
        steerTopic: (topic: string, direction: TodayFocusDirection) => ({ topic, direction }),
        setFocus: (focus: TodayBriefingFocus, source: TodayFocusSource | null) => ({ focus, source }),
    }),
    reducers({
        focus: [EMPTY_FOCUS as TodayBriefingFocus, { persist: true }, { setFocus: (_, { focus }) => focus }],
        focusDialogOpen: [false, { openFocusDialog: () => true, closeFocusDialog: () => false }],
        draft: [
            EMPTY_FOCUS as TodayBriefingFocus,
            {
                setDraft: (_, { draft }) => draft,
                setDraftTopic: (state, { topic, direction }) => withTopic(state, topic, direction),
                setDraftDuration: (state, { duration }) => ({ ...state, duration }),
            },
        ],
    }),
    selectors({
        currentFocus: [(s) => [s.focus, s.now], (focus: TodayBriefingFocus, now: number) => activeFocus(focus, now)],
        hasCurrentFocus: [(s) => [s.currentFocus], (focus: TodayBriefingFocus) => hasFocus(focus)],
        currentFocusSummary: [(s) => [s.currentFocus], (focus: TodayBriefingFocus) => focusSummary(focus)],
        draftTopics: [
            (s) => [s.draft, s.briefingItems, s.reports],
            (draft, briefingItems, reports): TodayFocusTopic[] => focusTopics(draft, briefingItems, reports),
        ],
    }),
    listeners(({ actions, values }) => ({
        // Each opening starts from what is saved, so a canceled edit does not come back.
        openFocusDialog: () => {
            actions.setDraft(values.currentFocus)
        },
        saveFocus: () => {
            const { draft } = values
            actions.setFocus({ ...draft, until: focusUntil(draft.duration, Date.now()) }, 'dialog')
            actions.closeFocusDialog()
        },
        clearFocus: () => {
            actions.setFocus(EMPTY_FOCUS, null)
        },
        steerTopic: ({ topic, direction }) => {
            const focus = withTopic(values.currentFocus, topic, direction)
            actions.setFocus({ ...focus, until: focusUntil(focus.duration, Date.now()) }, 'hover_card')
        },
        setFocus: ({ focus, source }) => {
            const directions = Object.values(focus.topics)
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('today briefing focus saved', {
                source,
                duration: focus.duration,
                more_topics: Object.keys(focus.topics).filter((key) => focus.topics[key] === 'more'),
                less_topics: Object.keys(focus.topics).filter((key) => focus.topics[key] === 'less'),
                topic_count: directions.length,
                cleared: directions.length === 0,
            })
        },
    })),
])
