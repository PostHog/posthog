import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'

import { todayFocusRetrieve, todayFocusUpdate } from 'products/today/frontend/generated/api'
import type { FocusTopicApi, FocusTopicDirectionEnumApi } from 'products/today/frontend/generated/api.schemas'

/** Where the person changed the focus, sent with the `today briefing focus saved` event. */
export type TodayFocusSource = 'hover_card' | 'focus_line'

/** The topics with one topic set to a direction, or without it when the direction is null. A changed topic moves to the end. */
export function withTopic(
    topics: FocusTopicApi[],
    topic: string,
    direction: FocusTopicDirectionEnumApi | null
): FocusTopicApi[] {
    const others = topics.filter((entry) => entry.topic !== topic)
    return direction ? [...others, { topic, direction }] : others
}

