export const todayHighlightsLogic = kea<todayHighlightsLogicType>([
    path(['scenes', 'project-homepage', 'today', 'todayHighlightsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),
    actions({
        highlightOpened: (item: HighlightItemApi, position: number) => ({ item, position }),
        pulseMetricOpened: (metric: HighlightMetricApi, position: number) => ({ metric, position }),
        pulseMetricPreviewed: (metric: HighlightMetricApi, position: number) => ({ metric, position }),
        hideHighlight: (item: HighlightItemApi, position: number) => ({ item, position }),
        unhideHighlight: (item: HighlightItemApi, position: number) => ({ item, position }),
        setHiddenHighlights: (hidden: Record<string, string>) => ({ hidden }),
        stopWaitingForHighlights: true,
        setPinnedPulseKeys: (metrics: PinnedPulseMetric[]) => ({ metrics }),
        pulseEditorOpened: true,
        togglePulsePin: (pin: PinnedPulseMetric, source: PulsePinSource) => ({ pin, source }),
        unpinAllPulse: true,
        holdPulseOrder: (keys: string[]) => ({ keys }),
        releasePulseOrder: true,
    }),
    loaders(({ values }) => ({
        pulseInsightResults: [
            [] as PinnedPulseMetric[],
            {
                loadPulseInsightResults: async (search: string, breakpoint) => {
                    await breakpoint(PULSE_SEARCH_DEBOUNCE_MS)
                    const pages = await Promise.all(
                        CHARTED_INSIGHT_KINDS.map((insight) =>
                            insightsList(String(values.currentProjectId), {
                                basic: true,
                                saved: true,
                                insight,
                                limit: PULSE_SEARCH_LIMIT,
                                order: '-last_viewed_at',
                                search: search.trim() || undefined,
                            })
                        )
                    )
                    breakpoint()
                    return pages
                        .flatMap((page) => page.results)
                        .sort((a, b) => (b.last_viewed_at ?? '').localeCompare(a.last_viewed_at ?? ''))
                        .filter((insight) => insight.short_id)
                        .map((insight) => ({
                            key: `insight:${insight.short_id}`,
                            name: insight.name || insight.derived_name || 'Untitled insight',
                        }))
                },
            },
        ],
        pulsePins: [
            [] as PulsePinApi[],
            {
                loadPulsePins: async (): Promise<PulsePinApi[]> => {
                    try {
                        return (await todayPulsePinsRetrieve(String(values.currentProjectId))).pins
                    } catch (error) {
                        if (error instanceof ApiError && error.status === 404) {
                            return []
                        }
                        throw error
                    }
                },
            },
        ],
        highlights: [
            null as HighlightsApi | null,
            {
                loadHighlights: async (): Promise<HighlightsApi | null> => {
                    if (values.currentProjectId === null) {
                        return null
                    }
                    try {
                        const loaded = await todayHighlightsRetrieve(String(values.currentProjectId))
                        const previous = values.highlights
                        return loaded.generated_at === null && previous?.generated_at
                            ? { ...previous, status: loaded.status }
                            : loaded
                    } catch (error) {
                        if (error instanceof ApiError && error.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        pulsePins: {
            setPinnedPulseKeys: (_, { metrics }) => metrics,
        },
        pulseOrderHeld: [
            null as string[] | null,
            {
                holdPulseOrder: (_, { keys }) => keys,
                releasePulseOrder: () => null,
            },
        ],
        hiddenHighlights: [
            {} as Record<string, string>,
            { persist: true },
            { setHiddenHighlights: (_, { hidden }) => hidden },
        ],
        highlightsHiddenNow: [
            [] as string[],
            {
                hideHighlight: (state, { item }) => [...state, item.key],
                unhideHighlight: (state, { item }) => state.filter((key) => key !== item.key),
            },
        ],
        highlightsWaitOver: [false, { stopWaitingForHighlights: () => true }],
        highlightsFailed: [
            false,
            {
                loadHighlights: () => false,
                loadHighlightsFailure: () => true,
            },
        ],
        highlights: {
            loadHighlightsFailure: () => null,
        },
    }),
    selectors({
        pinnedPulseMetrics: [(s) => [s.pulsePins], (pulsePins: PulsePinApi[]): PinnedPulseMetric[] => pulsePins],
        suggestedPulseMetrics: [
            (s) => [s.highlights, s.pinnedPulseMetrics],
            (highlights: HighlightsApi | null, pinnedPulseMetrics: PinnedPulseMetric[]): HighlightMetricApi[] =>
                (highlights?.pulse ?? []).filter(
                    (metric) => !pinnedPulseMetrics.some((pinned) => pinned.key === metric.key)
                ),
        ],
        pulseTiles: [
            (s) => [s.pinnedPulseMetrics, s.suggestedPulseMetrics, s.highlights, s.pulseOrderHeld],
            (
                pinnedPulseMetrics: PinnedPulseMetric[],
                suggestedPulseMetrics: HighlightMetricApi[],
                highlights: HighlightsApi | null,
                pulseOrderHeld: string[] | null
            ): TodayPulseTile[] => {
                const computing = highlights?.status === 'computing'
                const pinned: TodayPulseTile[] = pinnedPulseMetrics.map(
                    (pinned) =>
                        highlights?.pulse.find((metric) => metric.key === pinned.key) ?? {
                            ...pinned,
                            placeholder: computing ? 'computing' : 'unavailable',
                        }
                )
                const tiles = [...pinned, ...suggestedPulseMetrics].slice(0, Math.max(PULSE_TILES, pinned.length))
                if (!pulseOrderHeld) {
                    return tiles
                }
                const place = (key: string): number => {
                    const index = pulseOrderHeld.indexOf(key)
                    return index === -1 ? pulseOrderHeld.length : index
                }
                return [...tiles].sort((a, b) => place(a.key) - place(b.key))
            },
        ],
        highlightsPending: [
            (s) => [s.highlights, s.highlightsLoading],
            (highlights: HighlightsApi | null, highlightsLoading: boolean): boolean =>
                highlights ? highlights.status === 'computing' && highlights.generated_at === null : highlightsLoading,
        ],
        doneHighlightKeys: [
            (s) => [s.highlights, s.hiddenHighlights, s.highlightsHiddenNow, s.currentProjectId],
            (
                highlights: HighlightsApi | null,
                hiddenHighlights: Record<string, string>,
                highlightsHiddenNow: string[],
                currentProjectId: number | string
            ): string[] =>
                highlightsHiddenNow.filter(
                    (key) => hiddenHighlights[hiddenHighlightKey(currentProjectId, key)] === highlights?.day
                ),
        ],
        forYouHighlights: [
            (s) => [s.highlights, s.hiddenHighlights, s.doneHighlightKeys, s.currentProjectId],
            (
                highlights: HighlightsApi | null,
                hiddenHighlights: Record<string, string>,
                doneHighlightKeys: string[],
                currentProjectId: number | string
            ): HighlightItemApi[] =>
                (highlights?.items ?? []).filter(
                    (item) =>
                        hiddenHighlights[hiddenHighlightKey(currentProjectId, item.key)] !== highlights?.day ||
                        doneHighlightKeys.includes(item.key)
                ),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setPinnedPulseKeys: async ({ metrics }, breakpoint) => {
            await breakpoint(PULSE_PINS_SAVE_DEBOUNCE_MS)
            try {
                await todayPulsePinsUpdate(String(values.currentProjectId), { pins: metrics })
            } catch {
                toast.error({ title: "Couldn't save your numbers. Try again." })
                actions.loadPulsePins()
                return
            }
            breakpoint()
            actions.loadHighlights()
        },
        togglePulsePin: ({ pin, source }) => {
            const pinned = values.pinnedPulseMetrics.some((existing) => existing.key === pin.key)
            if (pulsePinLimitReason(values.pinnedPulseMetrics.length, pinned)) {
                return
            }
            actions.setPinnedPulseKeys(
                pinned
                    ? values.pinnedPulseMetrics.filter((existing) => existing.key !== pin.key)
                    : [...values.pinnedPulseMetrics, { key: pin.key, name: pin.name }]
            )
            posthog.capture(pinned ? 'today pulse number unpinned' : 'today pulse number pinned', {
                kind: pulseKind(pin.key),
                source,
                pinned_count: values.pinnedPulseMetrics.length,
            })
        },
        unpinAllPulse: () => {
            posthog.capture('today pulse numbers unpinned all', { pinned_count: values.pinnedPulseMetrics.length })
            actions.setPinnedPulseKeys([])
        },
        pulseEditorOpened: () => {
            posthog.capture('today pulse editor opened', { kept_count: values.pinnedPulseMetrics.length })
        },
        hideHighlight: ({ item, position }) => {
            const day = values.highlights?.day
            if (!day) {
                return
            }
            const kept = Object.fromEntries(
                Object.entries(values.hiddenHighlights).filter(([, hiddenOn]) => hiddenOn === day)
            )
            actions.setHiddenHighlights({ ...kept, [hiddenHighlightKey(values.currentProjectId, item.key)]: day })
            posthog.capture('today highlight hidden', {
                label: item.label,
                source: item.source,
                position,
                score: item.score,
            })
        },
        unhideHighlight: ({ item, position }) => {
            const { [hiddenHighlightKey(values.currentProjectId, item.key)]: _, ...rest } = values.hiddenHighlights
            actions.setHiddenHighlights(rest)
            posthog.capture('today highlight unhidden', {
                label: item.label,
                source: item.source,
                position,
                score: item.score,
            })
        },
        highlightOpened: ({ item, position }) => {
            posthog.capture('today highlight opened', {
                label: item.label,
                source: item.source,
                position,
                score: item.score,
            })
        },
        pulseMetricOpened: ({ metric, position }) => {
            posthog.capture('today pulse metric opened', {
                kind: pulseKind(metric.key),
                reason: metric.reason,
                position,
                pulse_ranking: posthog.getFeatureFlag(FEATURE_FLAGS.TODAY_PULSE_RANKING) ?? null,
            })
        },
        pulseMetricPreviewed: ({ metric, position }) => {
            const previewed: Set<string> = (cache.previewedPulseMetrics ??= new Set<string>())
            if (previewed.has(metric.key)) {
                return
            }
            previewed.add(metric.key)
            posthog.capture('today pulse metric previewed', {
                kind: pulseKind(metric.key),
                reason: metric.reason,
                position,
                pulse_ranking: posthog.getFeatureFlag(FEATURE_FLAGS.TODAY_PULSE_RANKING) ?? null,
            })
        },
        loadHighlightsSuccess: ({ highlights }) => {
            if (!highlights) {
                return
            }
            if (highlights.status === 'computing') {
                cache.disposables.add(() => {
                    const poll = window.setTimeout(() => actions.loadHighlights(), HIGHLIGHTS_POLL_MS)
                    return () => clearTimeout(poll)
                }, 'highlightsPoll')
                return
            }
            posthog.capture('today highlights loaded', {
                status: highlights.status,
                item_count: highlights.items.length,
                risk_count: highlights.items.filter((item) => item.label === 'risk').length,
                opportunity_count: highlights.items.filter((item) => item.label === 'opportunity').length,
                sources: highlights.items.map((item) => item.source),
                pulse_count: highlights.pulse.length,
                pulse_reasons: highlights.pulse.map((metric) => metric.reason),
                pulse_ranking: posthog.getFeatureFlag(FEATURE_FLAGS.TODAY_PULSE_RANKING) ?? null,
            })
        },
    })),
    afterMount(({ actions, cache }) => {
        actions.loadHighlights()
        actions.loadPulsePins()
        cache.disposables.add(() => {
            const timer = window.setTimeout(() => actions.stopWaitingForHighlights(), HIGHLIGHTS_WAIT_MS)
            return () => clearTimeout(timer)
        }, 'highlightsWait')
    }),
])
