import { MakeLogicType, actions, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { convertUniversalFiltersToRecordingsQuery } from 'scenes/session-recordings/filters/recordingsQueryConversions'
import { stripSessionIds } from 'scenes/session-recordings/playlist/playlistUtils'
import {
    asUniversalFilters,
    DEFAULT_RECORDING_FILTERS,
} from 'scenes/session-recordings/playlist/sessionRecordingsPlaylistLogic'

import type { LegacyRecordingFilters, RecordingUniversalFilters, SessionRecordingType } from '~/types'

import { sessionRecordingPlaylistsRetrieve } from 'products/replay/frontend/generated/api'
import type { HighlightItemApi } from 'products/today/frontend/generated/api.schemas'

export const TODAY_REPLAY_PREVIEW_LIMIT = 6

/** The saved filter a replay highlight points at, read from the `savedFilterId` its link carries. */
export function replaySavedFilterId(item: HighlightItemApi): string | null {
    if (item.source !== 'replay_saved_filters' || !item.url) {
        return null
    }
    return new URL(item.url, window.location.origin).searchParams.get('savedFilterId')
}

export interface TodayReplayPreviewLogicProps {
    savedFilterId: string
}

export interface TodayReplayPreview {
    recordings: SessionRecordingType[]
    hasMore: boolean
}

/** Unwatched recordings first, so the preview opens on one the viewer has not seen. */
export function unwatchedFirst(recordings: SessionRecordingType[]): SessionRecordingType[] {
    return [
        ...recordings.filter((recording) => !recording.viewed),
        ...recordings.filter((recording) => recording.viewed),
    ]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayReplayPreviewLogicValues {
    activeRecording: SessionRecordingType | null
    expanded: boolean
    preview: TodayReplayPreview | null
    previewLoading: boolean
    previewFailed: boolean
    selectedRecordingId: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayReplayPreviewLogicActions {
    loadPreview: () => void
    loadPreviewFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadPreviewSuccess: (
        preview: TodayReplayPreview | null,
        payload?: any
    ) => {
        preview: TodayReplayPreview | null
        payload?: any
    }
    selectRecording: (recordingId: string) => {
        recordingId: string
    }
    toggleExpanded: () => {
        value: true
    }
}

export type todayReplayPreviewLogicType = MakeLogicType<
    todayReplayPreviewLogicValues,
    todayReplayPreviewLogicActions,
    TodayReplayPreviewLogicProps
>

export const todayReplayPreviewLogic = kea<todayReplayPreviewLogicType>([
    path((savedFilterId) => ['scenes', 'project-homepage', 'today', 'todayReplayPreviewLogic', savedFilterId]),
    props({} as TodayReplayPreviewLogicProps),
    key((props) => props.savedFilterId),
    actions({
        toggleExpanded: true,
        selectRecording: (recordingId: string) => ({ recordingId }),
    }),
    loaders(({ props }) => ({
        preview: [
            null as TodayReplayPreview | null,
            {
                loadPreview: async () => {
                    const savedFilter = await sessionRecordingPlaylistsRetrieve('@current', props.savedFilterId)
                    // The serializer types `filters` as free JSON, so the generated type is `unknown`.
                    const stored = savedFilter.filters as RecordingUniversalFilters | LegacyRecordingFilters | null
                    const filters = stripSessionIds({ ...DEFAULT_RECORDING_FILTERS, ...asUniversalFilters(stored) })
                    // The generated sessionRecordingsList takes only limit and offset, not the query filters.
                    // nosemgrep: prefer-codegen-api-namespaced-replay
                    const response = await api.recordings.list({
                        ...convertUniversalFiltersToRecordingsQuery(filters),
                        limit: TODAY_REPLAY_PREVIEW_LIMIT,
                    })
                    return { recordings: unwatchedFirst(response.results), hasMore: !!response.has_next }
                },
            },
        ],
    })),
    reducers({
        expanded: [false, { toggleExpanded: (state) => !state }],
        selectedRecordingId: [null as string | null, { selectRecording: (_, { recordingId }) => recordingId }],
        previewFailed: [false, { loadPreview: () => false, loadPreviewFailure: () => true }],
    }),
    selectors({
        activeRecording: [
            (s) => [s.preview, s.selectedRecordingId],
            (preview: TodayReplayPreview | null, selectedRecordingId: string | null): SessionRecordingType | null =>
                preview?.recordings.find((recording: SessionRecordingType) => recording.id === selectedRecordingId) ??
                preview?.recordings[0] ??
                null,
        ],
    }),
    listeners(({ actions, values, props }) => ({
        toggleExpanded: () => {
            if (!values.expanded) {
                return
            }
            posthog.capture('today highlight previewed', { source: 'replay_saved_filters' })
            if (!values.preview && !values.previewLoading) {
                actions.loadPreview()
            }
        },
        selectRecording: ({ recordingId }) => {
            const position = values.preview?.recordings.findIndex((recording) => recording.id === recordingId) ?? -1
            posthog.capture('today replay preview recording selected', {
                saved_filter_id: props.savedFilterId,
                position: position + 1,
            })
        },
    })),
])
