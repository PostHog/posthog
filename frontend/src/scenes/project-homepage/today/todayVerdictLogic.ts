import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import posthog from 'posthog-js'

import { ApiError } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import { signalsReportsStateCreate } from 'products/signals/frontend/generated/api'
import type {
    SignalReportStateEnumApi,
    SignalReportStateRequestApi,
} from 'products/signals/frontend/generated/api.schemas'
import { openDismissReportDialog } from 'products/signals/frontend/inbox/components/shell/DismissReportDialog'
import { openResolveReportDialog } from 'products/signals/frontend/inbox/components/shell/ResolveReportDialog'
import { captureTodayReportAction } from 'products/signals/frontend/inbox/inboxAnalytics'
import { suppressDismissalPayload } from 'products/signals/frontend/inbox/utils/dismissalReasons'
import { withInboxWriteTimeout } from 'products/signals/frontend/inbox/utils/writeTimeout'

import type { TodayReportState } from './todayReportState'

/** What a person decides about a report from Today. */
export type TodayReportVerdict = 'resolve' | 'dismiss'

/** Where the person gave the verdict, sent with the `today report state changed` event. */
export type TodayReportVerdictSurface = 'briefing' | 'report_page'

/** The report a verdict acts on. */
export interface TodayReportVerdictTarget {
    reportId: string
    title: string
    /** The backend closes an open implementation pull request on either verdict, so the person confirms first. */
    hasOpenPullRequest: boolean
}

interface TodayReportVerdictCopy {
    apiState: SignalReportStateEnumApi
    itemState: TodayReportState
    success: string
    successClosingPullRequest: string
    failure: string
}

const VERDICTS: Record<TodayReportVerdict, TodayReportVerdictCopy> = {
    resolve: {
        apiState: 'resolved',
        itemState: 'done',
        success: 'Report resolved',
        successClosingPullRequest: 'Report resolved. Its pull request is closing.',
        failure: 'Couldn’t resolve the report. Try again, or resolve it from the Inbox.',
    },
    dismiss: {
        apiState: 'suppressed',
        itemState: 'dismissed',
        success: 'Report dismissed',
        successClosingPullRequest: 'Report dismissed. Its pull request is closing.',
        failure: 'Couldn’t dismiss the report. Try again, or dismiss it from the Inbox.',
    },
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayVerdictLogicValues {
    currentProjectId: number | string // teamLogic
    reportStateOverrides: Record<string, TodayReportState>
    reportVerdictDialogsOpen: Record<string, boolean>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayVerdictLogicActions {
    requestReportVerdict: (
        target: TodayReportVerdictTarget,
        verdict: TodayReportVerdict,
        surface: TodayReportVerdictSurface
    ) => {
        surface: TodayReportVerdictSurface
        target: TodayReportVerdictTarget
        verdict: TodayReportVerdict
    }
    setReportVerdict: (
        target: TodayReportVerdictTarget,
        verdict: TodayReportVerdict,
        surface: TodayReportVerdictSurface,
        feedback?: Omit<SignalReportStateRequestApi, 'state'>,
        onComplete?: (error?: unknown) => void
    ) => {
        feedback: Omit<SignalReportStateRequestApi, 'state'> | undefined
        onComplete: ((error?: unknown) => void) | undefined
        surface: TodayReportVerdictSurface
        target: TodayReportVerdictTarget
        verdict: TodayReportVerdict
    }
    setReportVerdictDialogOpen: (
        reportId: string,
        open: boolean
    ) => {
        open: boolean
        reportId: string
    }
    setReportVerdictFailure: (reportId: string) => {
        reportId: string
    }
}

export type todayVerdictLogicType = MakeLogicType<todayVerdictLogicValues, todayVerdictLogicActions>

export const todayVerdictLogic = kea<todayVerdictLogicType>([
    path(['scenes', 'project-homepage', 'today', 'todayVerdictLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),
    actions({
        setReportVerdictDialogOpen: (reportId: string, open: boolean) => ({ reportId, open }),
        requestReportVerdict: (
            target: TodayReportVerdictTarget,
            verdict: TodayReportVerdict,
            surface: TodayReportVerdictSurface
        ) => ({ target, verdict, surface }),
        setReportVerdict: (
            target: TodayReportVerdictTarget,
            verdict: TodayReportVerdict,
            surface: TodayReportVerdictSurface,
            feedback?: Omit<SignalReportStateRequestApi, 'state'>,
            onComplete?: (error?: unknown) => void
        ) => ({ target, verdict, surface, feedback, onComplete }),
        setReportVerdictFailure: (reportId: string) => ({ reportId }),
    }),
    reducers({
        reportVerdictDialogsOpen: [
            {} as Record<string, boolean>,
            {
                setReportVerdictDialogOpen: (dialogs, { reportId, open }) => {
                    if (open) {
                        return { ...dialogs, [reportId]: true }
                    }
                    const { [reportId]: _, ...rest } = dialogs
                    return rest
                },
            },
        ],
        // A verdict shows at once on the home and the report page. The next report load
        // gives the same state from the server, and a failed request takes the verdict back.
        reportStateOverrides: [
            {} as Record<string, TodayReportState>,
            {
                setReportVerdict: (overrides, { target, verdict }) => ({
                    ...overrides,
                    [target.reportId]: VERDICTS[verdict].itemState,
                }),
                setReportVerdictFailure: (overrides, { reportId }) => {
                    const { [reportId]: _, ...rest } = overrides
                    return rest
                },
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        requestReportVerdict: ({ target, verdict, surface }) => {
            if (values.reportStateOverrides[target.reportId] || values.reportVerdictDialogsOpen[target.reportId]) {
                return
            }
            actions.setReportVerdictDialogOpen(target.reportId, true)
            const onAfterClose = (): void => actions.setReportVerdictDialogOpen(target.reportId, false)
            let submission: Promise<void> | undefined
            const saveVerdict = (feedback: Omit<SignalReportStateRequestApi, 'state'>): Promise<void> => {
                if (!submission) {
                    submission = new Promise<void>((resolve, reject) => {
                        actions.setReportVerdict(target, verdict, surface, feedback, (error) => {
                            if (error) {
                                reject(error)
                            } else {
                                resolve()
                            }
                        })
                    }).catch((error) => {
                        submission = undefined
                        throw error
                    })
                }
                return submission
            }
            if (verdict === 'resolve') {
                openResolveReportDialog({
                    reportTitle: target.title,
                    hasOpenPr: target.hasOpenPullRequest,
                    submitDataAttr: 'today-report-resolve-confirm',
                    onAfterClose,
                    onConfirm: ({ reason, note }) =>
                        saveVerdict({
                            dismissal_reason: reason,
                            ...(note ? { dismissal_note: note } : {}),
                        }),
                })
            } else {
                openDismissReportDialog({
                    reportTitle: target.title,
                    hasOpenPr: target.hasOpenPullRequest,
                    submitDataAttr: 'today-report-dismiss-confirm',
                    onAfterClose,
                    onConfirm: (dismissal) => saveVerdict(suppressDismissalPayload(dismissal)),
                })
            }
        },
        setReportVerdict: async ({ target, verdict, surface, feedback, onComplete }) => {
            const copy = VERDICTS[verdict]
            try {
                await withInboxWriteTimeout('state', (options) =>
                    signalsReportsStateCreate(
                        String(values.currentProjectId),
                        target.reportId,
                        { ...feedback, state: copy.apiState },
                        options
                    )
                )
            } catch (error) {
                actions.setReportVerdictFailure(target.reportId)
                lemonToast.error((error instanceof ApiError && error.detail) || copy.failure)
                onComplete?.(error)
                return
            }
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('today report state changed', {
                report_id: target.reportId,
                verdict,
                surface,
                closed_pull_request: target.hasOpenPullRequest,
            })
            captureTodayReportAction({
                reportId: target.reportId,
                actionType: verdict,
                todaySurface: surface,
                extra: {
                    closed_pull_request: target.hasOpenPullRequest,
                    ...(feedback?.dismissal_reason ? { dismissal_reason: feedback.dismissal_reason } : {}),
                },
            })
            if (feedback?.dismissal_reason) {
                // pinned: analytics event name and properties. Renaming them breaks dashboards.
                posthog.capture('today report reason added', {
                    verdict,
                    reason: feedback.dismissal_reason,
                    has_note: !!feedback.dismissal_note,
                })
            }
            lemonToast.success(target.hasOpenPullRequest ? copy.successClosingPullRequest : copy.success)
            onComplete?.()
        },
    })),
])
