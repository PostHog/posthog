export const todayFeedLogic = kea<todayFeedLogicType>([
    path(['scenes', 'project-homepage', 'today', 'feed', 'todayFeedLogic']),
    connect(() => ({
        values: [
            featurePreviewsLogic,
            ['earlyAccessFeatures', 'rawEarlyAccessFeaturesLoading'],
            teamLogic,
            ['currentProjectId', 'currentTeam'],
        ],
        actions: [featurePreviewsLogic, ['loadEarlyAccessFeatures', 'updateEarlyAccessFeatureEnrollment']],
    })),
    actions({
        postOpened: (post: TodayFeedPost, position: number) => ({ post, position }),
        postPlayed: (post: TodayFeedPost, position: number) => ({ post, position }),
        postHidden: (post: TodayFeedPost, position: number) => ({ post, position }),
        postLiked: (post: TodayFeedPost, position: number, liked: boolean) => ({ post, position, liked }),
        postEnrolled: (post: TodayFeedPost, position: number) => ({ post, position }),
        endReached: (postCount: number) => ({ postCount }),
        setHiddenFeedKeys: (hidden: Record<string, true>) => ({ hidden }),
        setLikedFeedKeys: (liked: Record<string, true>) => ({ liked }),
    }),
    loaders(({ values }) => ({
        eventCounts: [
            null as DayCount[] | null,
            {
                loadEventCounts: async () => {
                    try {
                        const response = await api.queryHogQL<[string, number, number][]>(
                            hogql`SELECT event, dateDiff('day', toDate(timestamp), today()) AS days_ago, count() AS events
                                FROM events
                                WHERE timestamp >= toStartOfDay(now()) - toIntervalDay(${FEED_DAYS})
                                    AND timestamp < toStartOfDay(now())
                                GROUP BY event, days_ago
                                LIMIT 20000`,
                            { ...QUERY_TAGS, name: 'today_feed_event_counts' }
                        )
                        return response.results.map(([name, daysAgo, count]) => ({ name, daysAgo, count }))
                    } catch (error) {
                        posthog.captureException(error)
                        return []
                    }
                },
            },
        ],
        scoutReports: [
            null as FeedScoutReport[] | null,
            {
                loadScoutReports: async () => {
                    try {
                        const response = await signalsReportsList(String(values.currentProjectId), {
                            scope: 'entire_project',
                            ordering: '-created_at',
                            created_after: dayjs().subtract(SCOUT_REPORT_DAYS, 'day').toISOString(),
                            limit: 50,
                        })
                        return response.results
                    } catch (error) {
                        posthog.captureException(error)
                        return []
                    }
                },
            },
        ],
        replayPicks: [
            null as HighlightFeedItemApi[] | null,
            {
                loadReplayPicks: async () => {
                    try {
                        const response = await visionScannersHighlightFeedRetrieve(String(values.currentProjectId))
                        return response.results
                    } catch {
                        // Most projects have no Replay Vision scanners, so the rage click fallback covers them.
                        return []
                    }
                },
            },
        ],
        rageSession: [
            null as RageSession | null,
            {
                loadRageSession: async () => {
                    if (!values.currentTeam?.session_recording_opt_in) {
                        return null
                    }
                    try {
                        const response = await api.queryHogQL<[string, number, string | null, string][]>(
                            hogql`SELECT properties.$session_id AS session_id, count() AS clicks, argMax(properties.$current_url, timestamp) AS url, min(timestamp) AS started_at
                                FROM events
                                WHERE event = '$rageclick'
                                    AND timestamp >= now() - toIntervalDay(7)
                                    AND notEmpty(properties.$session_id)
                                    AND properties.$session_id IN (
                                        SELECT session_id FROM raw_session_replay_events
                                        WHERE min_first_timestamp >= now() - toIntervalDay(8)
                                    )
                                GROUP BY session_id
                                ORDER BY clicks DESC
                                LIMIT 1`,
                            { ...QUERY_TAGS, name: 'today_feed_rage_session' }
                        )
                        const [row] = response.results
                        return row ? { sessionId: row[0], clicks: row[1], url: row[2], startedAt: row[3] } : null
                    } catch (error) {
                        posthog.captureException(error)
                        return null
                    }
                },
            },
        ],
    })),
    reducers({
        hiddenFeedKeys: [
            {} as Record<string, true>,
            { persist: true },
            { setHiddenFeedKeys: (_, { hidden }) => hidden },
        ],
        likedFeedKeys: [{} as Record<string, true>, { persist: true }, { setLikedFeedKeys: (_, { liked }) => liked }],
        enrolledFlagKeys: [
            {} as Record<string, true>,
            {
                postEnrolled: (state, { post }) =>
                    post.media?.type === 'card' && post.media.enrollFlagKey
                        ? { ...state, [post.media.enrollFlagKey]: true }
                        : state,
            },
        ],
    }),
    selectors({
        hiddenKeys: [
            (s) => [s.hiddenFeedKeys, s.currentProjectId],
            (hiddenFeedKeys: Record<string, true>, currentProjectId: number | string): Record<string, true> =>
                keysForProject(hiddenFeedKeys, currentProjectId),
        ],
        likedKeys: [
            (s) => [s.likedFeedKeys, s.currentProjectId],
            (likedFeedKeys: Record<string, true>, currentProjectId: number | string): Record<string, true> =>
                keysForProject(likedFeedKeys, currentProjectId),
        ],
        feedReady: [
            (s) => [
                s.scoutReports,
                s.eventCounts,
                s.replayPicks,
                s.rageSessionLoading,
                s.rawEarlyAccessFeaturesLoading,
            ],
            (
                scoutReports: FeedScoutReport[] | null,
                eventCounts: DayCount[] | null,
                replayPicks: HighlightFeedItemApi[] | null,
                rageSessionLoading: boolean,
                rawEarlyAccessFeaturesLoading: boolean
            ): boolean =>
                scoutReports !== null &&
                eventCounts !== null &&
                replayPicks !== null &&
                !rageSessionLoading &&
                !rawEarlyAccessFeaturesLoading,
        ],
        feedPosts: [
            (s) => [
                s.currentTeam,
                s.scoutReports,
                s.eventCounts,
                s.replayPicks,
                s.rageSession,
                s.earlyAccessFeatures,
                s.hiddenKeys,
            ],
            (
                currentTeam: TeamPublicType | TeamType | null,
                scoutReports: FeedScoutReport[] | null,
                eventCounts: DayCount[] | null,
                replayPicks: HighlightFeedItemApi[] | null,
                rageSession: RageSession | null,
                earlyAccessFeatures: EnrichedEarlyAccessFeature[],
                hiddenKeys: Record<string, true>
            ): TodayFeedPost[] =>
                buildFeed({
                    team: currentTeam,
                    today: dayjs(),
                    scoutReports: scoutReports ?? [],
                    eventCounts: eventCounts ?? [],
                    replayPicks: replayPicks ?? [],
                    rageSession,
                    previews: earlyAccessFeatures.map((feature) => ({
                        flagKey: feature.flagKey,
                        name: feature.name,
                        description: feature.description,
                        stage: feature.stage,
                        enabled: feature.enabled,
                    })),
                    hiddenKeys,
                }),
        ],
    }),
    // pinned: analytics event names and properties, renaming breaks the feed's dashboards
    listeners(({ actions, values, cache }) => ({
        postOpened: ({ post, position }) => {
            posthog.capture('today feed post opened', { kind: post.kind, product: post.product, position })
        },
        postPlayed: ({ post, position }) => {
            posthog.capture('today feed recording played', { kind: post.kind, position })
        },
        postHidden: ({ post, position }) => {
            actions.setHiddenFeedKeys(
                toggled(values.hiddenFeedKeys, scopedKey(values.currentProjectId, post.key), true)
            )
            posthog.capture('today feed post hidden', { kind: post.kind, product: post.product, position })
        },
        postLiked: ({ post, position, liked }) => {
            actions.setLikedFeedKeys(toggled(values.likedFeedKeys, scopedKey(values.currentProjectId, post.key), liked))
            posthog.capture('today feed post liked', { kind: post.kind, product: post.product, position, liked })
        },
        postEnrolled: ({ post, position }) => {
            if (post.media?.type === 'card' && post.media.enrollFlagKey) {
                actions.updateEarlyAccessFeatureEnrollment(post.media.enrollFlagKey, true, 'beta')
                posthog.capture('today feed preview turned on', { position, flag_key: post.media.enrollFlagKey })
            }
        },
        endReached: ({ postCount }) => {
            if (!cache.endCaptured) {
                cache.endCaptured = true
                posthog.capture('today feed end reached', { post_count: postCount })
            }
        },
    })),
    subscriptions(({ values, cache }) => ({
        feedReady: (feedReady: boolean) => {
            if (feedReady && !cache.loadCaptured) {
                cache.loadCaptured = true
                posthog.capture('today feed viewed', {
                    post_count: values.feedPosts.length,
                    kinds: values.feedPosts.map((post) => post.kind),
                })
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadScoutReports()
        actions.loadEventCounts()
        actions.loadReplayPicks()
        actions.loadRageSession()
        actions.loadEarlyAccessFeatures()
    }),
])
