function scopedKey(projectId: number | string, key: string): string {
    return `${projectId}:${key}`
}

function keysForProject(scoped: Record<string, true>, projectId: number | string): Record<string, true> {
    const prefix = scopedKey(projectId, '')
    const keys: Record<string, true> = {}
    for (const key of Object.keys(scoped)) {
        if (key.startsWith(prefix)) {
            keys[key.slice(prefix.length)] = true
        }
    }
    return keys
}

function toggled(scoped: Record<string, true>, key: string, on: boolean): Record<string, true> {
    const next = { ...scoped }
    if (on) {
        next[key] = true
    } else {
        delete next[key]
    }
    return next
}

