export type TodayFlowPhase = 'question' | 'thinking' | 'results'

export interface TodayFlowLogicProps {
    conversationId: string
    scenarioId: TodayScenarioId
    question: string
    /** Reopening a finished conversation skips the thinking and shows every card ready. */
    resumed?: boolean
    initialEvidenceId?: string | null
}

export interface TodayChatMessage {
    from: 'you' | 'posthog'
    text: string
}

export const QUESTION_MS = 700
export const FIRST_THOUGHT_MS = 1800
export const THOUGHT_MS = 1200
export const PREPARING_MS = 1500
export const RECOMMENDATION_MS = 1900
export const REPLY_MS = 1400

/** The lines shown while the flow thinks, each with how long it stays. */
export function thinkingLines(scenario: TodayScenario): { text: string; duration: number }[] {
    return [
        { text: 'Hmm, let’s figure this out together.', duration: FIRST_THOUGHT_MS },
        ...scenario.thinking.map((line) => ({ text: `${line}…`, duration: THOUGHT_MS })),
        { text: 'Preparing problem board…', duration: PREPARING_MS },
    ]
}

/** How the chat answers a question about one piece of evidence. */
export function evidenceReply(evidence: TodayScenarioEvidence, question: string): string {
    const first = evidence.steps[0]
    const last = evidence.steps[evidence.steps.length - 1]
    return `Looking at ${evidence.source.toLowerCase()}: ${first.label.toLowerCase()} sits at ${first.value}, against ${last.value} for ${last.label.toLowerCase()}. For “${question}”, I’d start with the change above and check this again a week after it ships.`
}

function leadingNumber(value: string): number | null {
    const match = value.replace(/,/g, '').match(/-?\d+(\.\d+)?/)
    return match ? Number(match[0]) : null
}

/** How a breakdown row compares with the first row: points between two percentages, otherwise relative change. */
export function breakdownDelta(first: string, current: string, index: number): string {
    if (index === 0) {
        return 'Baseline'
    }
    const base = leadingNumber(first)
    const value = leadingNumber(current)
    if (base === null || value === null || base === 0) {
        return ''
    }
    const bothPercent = first.includes('%') && current.includes('%')
    const change = bothPercent ? value - base : ((value - base) / base) * 100
    const sign = change > 0 ? '+' : change < 0 ? '−' : '±'
    return `${sign}${Math.abs(Math.round(change))}${bothPercent ? ' pts' : '%'}`
}

