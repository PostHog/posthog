export const todayFlowLogic: LogicWrapper<todayFlowLogicType> = kea<todayFlowLogicType>([
    props({} as TodayFlowLogicProps),
    key((props) => props.conversationId),
    path((key) => ['scenes', 'project-homepage', 'today', 'todayFlowLogic', key]),
    actions({
        setPhase: (phase: TodayFlowPhase) => ({ phase }),
        setThoughtIndex: (index: number) => ({ index }),
        markEvidenceReady: (evidenceId: string) => ({ evidenceId }),
        openEvidence: (evidenceId: string) => ({ evidenceId }),
        closeEvidence: true,
        markRecommendationReady: (evidenceId: string) => ({ evidenceId }),
        land: (evidenceId: string) => ({ evidenceId }),
        addToToday: (evidenceId: string) => ({ evidenceId }),
        remind: (evidenceId: string, optionId: string) => ({ evidenceId, optionId }),
        send: (evidenceId: string, optionId: string) => ({ evidenceId, optionId }),
        toggleVoice: true,
        setVoice: (voice: boolean) => ({ voice }),
        askAboutEvidence: (evidenceId: string, question: string) => ({ evidenceId, question }),
        receiveReply: (evidenceId: string, text: string) => ({ evidenceId, text }),
    }),
    reducers(({ props }) => ({
        phase: [(props.resumed ? 'results' : 'question') as TodayFlowPhase, { setPhase: (_, { phase }) => phase }],
        thoughtIndex: [0, { setThoughtIndex: (_, { index }) => index }],
        readyEvidenceIds: [
            props.resumed ? SCENARIOS[props.scenarioId].evidence.map((evidence) => evidence.id) : ([] as string[]),
            {
                markEvidenceReady: (state, { evidenceId }) =>
                    state.includes(evidenceId) ? state : [...state, evidenceId],
            },
        ],
        openEvidenceId: [
            (props.initialEvidenceId ?? null) as string | null,
            {
                openEvidence: (_, { evidenceId }) => evidenceId,
                closeEvidence: () => null,
            },
        ],
        readyRecommendationIds: [
            props.initialEvidenceId ? [props.initialEvidenceId] : ([] as string[]),
            {
                markRecommendationReady: (state, { evidenceId }) =>
                    state.includes(evidenceId) ? state : [...state, evidenceId],
            },
        ],
        landedIds: [
            [] as string[],
            { land: (state, { evidenceId }) => (state.includes(evidenceId) ? state : [...state, evidenceId]) },
        ],
        reminders: [
            {} as Record<string, string>,
            { remind: (state, { evidenceId, optionId }) => ({ ...state, [evidenceId]: optionId }) },
        ],
        sentTo: [
            {} as Record<string, string>,
            { send: (state, { evidenceId, optionId }) => ({ ...state, [evidenceId]: optionId }) },
        ],
        voice: [
            false,
            {
                toggleVoice: (state) => !state,
                setVoice: (_, { voice }) => voice,
                openEvidence: () => false,
            },
        ],
        chats: [
            {} as Record<string, TodayChatMessage[]>,
            {
                askAboutEvidence: (state, { evidenceId, question }) => ({
                    ...state,
                    [evidenceId]: [...(state[evidenceId] ?? []), { from: 'you', text: question }],
                }),
                receiveReply: (state, { evidenceId, text }) => ({
                    ...state,
                    [evidenceId]: [...(state[evidenceId] ?? []), { from: 'posthog', text }],
                }),
            },
        ],
        typingEvidenceId: [
            null as string | null,
            {
                askAboutEvidence: (_, { evidenceId }) => evidenceId,
                receiveReply: () => null,
            },
        ],
    })),
    selectors({
        scenario: [() => [(_, props) => props.scenarioId], (scenarioId: TodayScenarioId) => SCENARIOS[scenarioId]],
        thoughts: [(s) => [s.scenario], (scenario: TodayScenario) => thinkingLines(scenario)],
        openEvidence: [
            (s) => [s.scenario, s.openEvidenceId],
            (scenario: TodayScenario, openEvidenceId: string | null): TodayScenarioEvidence | null =>
                scenario.evidence.find((evidence) => evidence.id === openEvidenceId) ?? null,
        ],
        readyImpact: [
            (s) => [s.scenario, s.readyEvidenceIds],
            (scenario: TodayScenario, readyEvidenceIds: string[]): number =>
                scenario.evidence
                    .filter((evidence) => readyEvidenceIds.includes(evidence.id))
                    .reduce((total, evidence) => total + (evidence.impact ?? 0), 0),
        ],
        allReady: [
            (s) => [s.scenario, s.readyEvidenceIds],
            (scenario: TodayScenario, readyEvidenceIds: string[]): boolean =>
                scenario.evidence.every((evidence) => readyEvidenceIds.includes(evidence.id)),
        ],
        targetReached: [
            (s) => [s.scenario, s.allReady, s.readyImpact],
            (scenario: TodayScenario, allReady: boolean, readyImpact: number): boolean =>
                !!scenario.target && allReady && 1 + readyImpact >= scenario.target.goal,
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        setPhase: ({ phase }) => {
            if (phase !== 'results') {
                return
            }
            todayLogic.findMounted()?.actions.markConversationAnswered(props.conversationId)
            for (const evidence of values.scenario.evidence) {
                if (evidence.readyAfter <= 0) {
                    actions.markEvidenceReady(evidence.id)
                }
            }
            cache.disposables.add(
                () => {
                    const timers = values.scenario.evidence
                        .filter((evidence) => evidence.readyAfter > 0)
                        .map((evidence) =>
                            window.setTimeout(() => actions.markEvidenceReady(evidence.id), evidence.readyAfter)
                        )
                    return () => timers.forEach((timer) => clearTimeout(timer))
                },
                'evidence',
                { pauseOnPageHidden: false }
            )
        },
        openEvidence: ({ evidenceId }) => {
            if (values.readyRecommendationIds.includes(evidenceId)) {
                return
            }
            cache.disposables.add(
                () => {
                    const timer = window.setTimeout(
                        () => actions.markRecommendationReady(evidenceId),
                        RECOMMENDATION_MS
                    )
                    return () => clearTimeout(timer)
                },
                `recommendation-${evidenceId}`,
                { pauseOnPageHidden: false }
            )
        },
        addToToday: ({ evidenceId }) => {
            const evidence = values.scenario.evidence.find((item) => item.id === evidenceId)
            if (!evidence) {
                return
            }
            todayLogic.findMounted()?.actions.addTodayItem({
                evidenceId,
                title: evidence.title,
                action: evidence.action,
                color: evidence.color,
                scenarioId: props.scenarioId,
                conversationId: props.conversationId,
            })
        },
        askAboutEvidence: ({ evidenceId, question }) => {
            const evidence = values.scenario.evidence.find((item) => item.id === evidenceId)
            if (!evidence) {
                return
            }
            cache.disposables.add(
                () => {
                    const timer = window.setTimeout(
                        () => actions.receiveReply(evidenceId, evidenceReply(evidence, question)),
                        REPLY_MS
                    )
                    return () => clearTimeout(timer)
                },
                `reply-${evidenceId}`,
                { pauseOnPageHidden: false }
            )
        },
    })),
    afterMount(({ actions, values, props, cache }) => {
        if (props.initialEvidenceId) {
            actions.openEvidence(props.initialEvidenceId)
        }
        if (props.resumed) {
            return
        }
        cache.disposables.add(
            () => {
                const timers: number[] = [window.setTimeout(() => actions.setPhase('thinking'), QUESTION_MS)]
                let elapsed = QUESTION_MS
                values.thoughts.forEach((thought, index) => {
                    if (index > 0) {
                        timers.push(window.setTimeout(() => actions.setThoughtIndex(index), elapsed))
                    }
                    elapsed += thought.duration
                })
                timers.push(window.setTimeout(() => actions.setPhase('results'), elapsed))
                return () => timers.forEach((timer) => clearTimeout(timer))
            },
            'thinking',
            { pauseOnPageHidden: false }
        )
    }),
])
