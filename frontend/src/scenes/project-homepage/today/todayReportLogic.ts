export const todayReportLogic = kea<todayReportLogicType>([
    props({} as TodayReportLogicProps),
    key((props) => props.reportId),
    path((reportId) => ['scenes', 'project-homepage', 'today', 'todayReportLogic', reportId]),
    connect(() => ({ values: [todayLogic, ['reports', 'reportStateOverrides'], featureFlagLogic, ['featureFlags']] })),
    actions({
        evidenceOpened: (signal: SignalNodeApi, destination: TodaySignalDestination['kind'] | 'code' | 'slack') => ({
            signal,
            destination,
        }),
        loadCodeFile: (file: TodayCodeFile) => ({ file }),
        codeFileLoaded: (key: string, file: RepositoryFileApi | null) => ({ key, file }),
        loadKeyClauses: (requests: TodayKeyClauseRequest[]) => ({ requests }),
        keyClausesLoaded: (found: Record<string, TodayKeyClause[]>) => ({ found }),
        chooseExcerpt: (key: string, finding: string, excerpts: string[]) => ({ key, finding, excerpts }),
        excerptChosen: (key: string, index: number | null) => ({ key, index }),
    }),
    loaders(({ props }) => ({
        fullReport: [
            null as SignalReport | null,
            {
                loadFullReport: async () => {
                    if (isSampleReportId(props.reportId)) {
                        const report = findSampleReport(props.reportId)
                        if (!report) {
                            throw new Error('Sample report not found')
                        }
                        return report
                    }
                    // nosemgrep: prefer-codegen-api-namespaced-signals -- Today passes reports to the Inbox's helpers, which take the handwritten SignalReport. The generated report type is wider (string status and priority, read-only arrays), so this call moves to generated types together with the Inbox.
                    return await api.signalReports.get(props.reportId)
                },
            },
        ],
        reportSignals: [
            null as SignalNodeApi[] | null,
            {
                loadReportSignals: async (): Promise<SignalNodeApi[]> => {
                    if (isSampleReportId(props.reportId)) {
                        return sampleSignals(props.reportId)
                    }
                    const response = await signalsReportsSignalsRetrieve(requestProjectId(), props.reportId)
                    return response.signals
                },
            },
        ],
    })),
    reducers({
        reportFailed: [false, { loadFullReport: () => false, loadFullReportFailure: () => true }],
        // A file is read once per page. A failed read is kept as null, so the row falls back to its link.
        codeFiles: [
            {} as Record<string, TodayCodeFileState>,
            {
                loadCodeFile: (state, { file }) =>
                    codeFileKey(file) in state ? state : { ...state, [codeFileKey(file)]: 'loading' },
                codeFileLoaded: (state, { key, file }) => ({ ...state, [key]: file }),
            },
        ],
        excerptChoices: [
            {} as Record<string, TodayExcerptChoice>,
            {
                chooseExcerpt: (state, { key }) => (key in state ? state : { ...state, [key]: 'pending' }),
                excerptChosen: (state, { key, index }) => ({ ...state, [key]: index }),
            },
        ],
        keyClauses: [
            {} as Record<string, TodayKeyClause[]>,
            { keyClausesLoaded: (state, { found }) => ({ ...state, ...found }) },
        ],
    }),
    selectors(({ props }) => ({
        // The list row renders at once, and the full report replaces it when it arrives with its charts.
        // A failed load shows its error instead, so the page never passes off the list row as the report.
        currentReport: [
            (s) => [s.fullReport, s.reports, s.reportFailed],
            (fullReport: SignalReport | null, reports: SignalReport[], reportFailed: boolean): SignalReport | null =>
                reportFailed ? null : (fullReport ?? reports.find((report) => report.id === props.reportId) ?? null),
        ],
        sections: [
            (s) => [s.currentReport],
            (currentReport: SignalReport | null): TodayReportSections => todayReportSections(currentReport?.summary),
        ],
        // The API returns signals oldest first, and the newest one is the most useful to read first.
        signals: [
            (s) => [s.reportSignals],
            (reportSignals: SignalNodeApi[] | null): SignalNodeApi[] =>
                [...(reportSignals ?? [])].sort(
                    (first, second) => new Date(second.timestamp).getTime() - new Date(first.timestamp).getTime()
                ),
        ],
        // A verdict given from Today shows before the report reloads.
        reportState: [
            (s) => [s.currentReport, s.reportStateOverrides],
            (
                currentReport: SignalReport | null,
                reportStateOverrides: Record<string, BriefingItemStateEnumApi>
            ): BriefingItemStateEnumApi =>
                reportStateOverrides[props.reportId] ??
                (currentReport ? reportItemState(currentReport.status) : 'open'),
        ],
        jevEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TODAY_REPORT_JEV],
        ],
        // Absolute, because the implementation prompt gives it to the agent so the agent can read the report.
        reportUrl: [
            () => [],
            (): string =>
                `${window.location.origin}${addProjectIdIfMissing(urls.inboxReport('reports', props.reportId))}`,
        ],
    })),
    listeners(({ props, values, actions }) => ({
        loadFullReportSuccess: () => {
            const report = values.currentReport
            const sections = values.sections
            const requests: TodayKeyClauseRequest[] = [
                { text: renderedText(sections.lead), roles: ['problem', 'cause'] },
                { text: renderedText(impactSentence(sections)), roles: ['problem', 'cause'] },
                { text: report ? renderedText(reportProposal(report, sections)) : '', roles: ['fix'] },
            ]
            actions.loadKeyClauses(requests.filter((request) => request.text))
        },
        chooseExcerpt: async ({ key, finding, excerpts }) => {
            if (values.excerptChoices[key] !== 'pending') {
                return
            }
            if (!values.jevEnabled || isSampleReportId(props.reportId)) {
                actions.excerptChosen(key, null)
                return
            }
            const cacheKey = jevCacheKey('excerpt', finding, ...excerpts)
            const cached = readJevCache<number | null>(cacheKey)
            if (cached !== undefined) {
                actions.excerptChosen(key, cached)
                return
            }
            try {
                const choice = await fetchExcerptChoice(finding, excerpts)
                writeJevCache(cacheKey, choice)
                actions.excerptChosen(key, choice)
            } catch {
                actions.excerptChosen(key, null)
            }
        },
        loadKeyClauses: async ({ requests }) => {
            const missing = requests.filter((request) => !(request.text in values.keyClauses))
            if (!missing.length || !values.jevEnabled || isSampleReportId(props.reportId)) {
                return
            }
            const summary = values.currentReport?.summary ?? ''
            const cacheKey = jevCacheKey('marks', summary, ...missing.map((request) => request.text))
            const cached = readJevCache<Record<string, TodayKeyClause[]>>(cacheKey)
            if (cached) {
                actions.keyClausesLoaded(cached)
                return
            }
            try {
                const found = await fetchKeyClauses(missing, summary)
                writeJevCache(cacheKey, found)
                actions.keyClausesLoaded(found)
            } catch {
                actions.keyClausesLoaded(Object.fromEntries(missing.map((request) => [request.text, []])))
            }
        },
        loadCodeFile: async ({ file }) => {
            const key = codeFileKey(file)
            if (values.codeFiles[key] !== 'loading' || isSampleReportId(props.reportId)) {
                return
            }
            try {
                actions.codeFileLoaded(
                    key,
                    await businessKnowledgeRepositoriesFileRetrieve(requestProjectId(), {
                        repo: file.repo,
                        path: file.path,
                    })
                )
            } catch {
                actions.codeFileLoaded(key, null)
            }
        },
        evidenceOpened: ({ signal, destination }) => {
            posthog.capture('today report evidence opened', {
                report_id: props.reportId,
                source_product: signal.source_product,
                source_type: signal.source_type,
                destination,
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadFullReport()
        actions.loadReportSignals()
    }),
])
