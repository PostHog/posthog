import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { addProjectIdIfMissing } from 'lib/utils/kea-router'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { signalsReportsSignalsRetrieve } from 'products/signals/frontend/generated/api'
import { ReportChartApi, SignalNodeApi } from 'products/signals/frontend/generated/api.schemas'
import { SignalReport } from 'products/signals/frontend/inbox/types'
import type { BriefingItemStateEnumApi } from 'products/today/frontend/generated/api.schemas'

import { reportItemState } from './todayBriefingItems'
import { todayLogic } from './todayLogic'
import { TodayReportSections, type TodaySignalDestination, todayReportSections } from './todayReportPresentation'
import { findSampleReport, isSampleReportId, sampleSignals } from './todaySampleReports'

export interface TodayReportLogicProps {
    reportId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayReportLogicValues {
    reportStateOverrides: Record<string, BriefingItemStateEnumApi> // todayLogic
    reports: SignalReport[] // todayLogic
    chartsById: Map<string, ReportChartApi>
    currentReport: SignalReport | null
    fullReport: SignalReport | null
    fullReportLoading: boolean
    reportFailed: boolean
    reportSignals: SignalNodeApi[] | null
    reportSignalsLoading: boolean
    reportState: BriefingItemStateEnumApi
    reportUrl: string
    sections: TodayReportSections
    signals: SignalNodeApi[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayReportLogicActions {
    evidenceOpened: (
        signal: SignalNodeApi,
        destination: TodaySignalDestination['kind']
    ) => {
        signal: SignalNodeApi
        destination: TodaySignalDestination['kind']
    }
    loadFullReport: () => any
    loadFullReportFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFullReportSuccess: (
        fullReport: SignalReport,
        payload?: any
    ) => {
        fullReport: SignalReport
        payload?: any
    }
    loadReportSignals: () => any
    loadReportSignalsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadReportSignalsSuccess: (
        reportSignals: SignalNodeApi[],
        payload?: any
    ) => {
        reportSignals: SignalNodeApi[]
        payload?: any
    }
}

