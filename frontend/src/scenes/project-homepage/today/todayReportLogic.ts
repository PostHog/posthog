export type TodayCodeFileState = RepositoryFileApi | null | 'loading'
export type TodayExcerptChoice = number | null | 'pending'

export function codeFileKey(file: TodayCodeFile): string {
    return `${file.repo}:${file.path}`
}

// The team can still be loading on a direct visit, so the id falls back to the app context and the URL.
function requestProjectId(): string {
    return String(
        teamLogic.values.currentTeamId ??
            getCurrentTeamIdOrNone() ??
            getProjectIdentifierInPath(window.location.pathname)
    )
}

