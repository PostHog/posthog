export const todayReportLogic = kea<todayReportLogicType>([
    props({} as TodayReportLogicProps),
    key((props) => props.reportId),
    path((reportId) => ['scenes', 'project-homepage', 'today', 'todayReportLogic', reportId]),
    connect(() => ({
        values: [
            teamLogic,
            ['currentTeamId', 'currentProjectId'],
            todayLogic,
            ['reports', 'askingAi', 'reportOpenContext'],
            todayVerdictLogic,
            ['reportStateOverrides'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [
            todayLogic,
            ['askAi', 'setReportOpenContext'],
            inboxTaskKickoffLogic,
            ['createPrFromReport', 'discussReport', 'openReportDiscussion'],
        ],
    })),
    actions({
        evidenceOpened: (signal: SignalViewApi, destination: TodaySignalDestination['kind'] | 'code' | 'slack') => ({
            signal,
            destination,
        }),
        readCode: (signal: SignalViewApi, files: CodeFileApi[]) => ({ signal, files }),
        codeQuoteRead: (signalId: string, quote: TodayCodeQuoteState) => ({ signalId, quote }),
        codeQuoteCleared: (signalId: string) => ({ signalId }),
        codeQuotePicksCleared: true,
        askAboutReport: (question: string) => ({ question }),
        expandEvidence: (signalId: string) => ({ signalId }),
        collapseEvidence: (signalId: string) => ({ signalId }),
        openComposer: true,
        setDraft: (draft: string) => ({ draft }),
        startWithPostHog: true,
        markOpened: (kind: TodayMarkKind) => ({ kind }),
        reportVisited: true,
    }),
    loaders(({ props, values, cache }) => ({
        fullReport: [
            null as SignalReport | null,
            {
                loadFullReport: async () => {
                    if (values.isSample) {
                        const report = findSampleReport(props.reportId)
                        if (!report) {
                            throw new Error('Sample report not found')
                        }
                        return report
                    }
                    // nosemgrep: prefer-codegen-api-namespaced-signals -- Today passes reports to the Inbox's helpers, which take the handwritten SignalReport. The generated report type is wider (string status and priority, read-only arrays), so this call moves to generated types together with the Inbox.
                    return await api.signalReports.get(props.reportId)
                },
            },
        ],
        page: [
            null as ReportPageApi | null,
            {
                loadPage: async (): Promise<ReportPageApi> =>
                    await todayReportsPageRetrieve(String(values.currentProjectId), props.reportId),
            },
        ],
        figureMarks: [
            null as FigureMarkApi[] | null,
            {
                loadFigureMarks: async (): Promise<FigureMarkApi[] | null> => {
                    if (!values.asksJev) {
                        return values.figureMarks
                    }
                    cache.figureMarks ??= todayReportsFigureMarksRetrieve(
                        String(values.currentProjectId),
                        props.reportId
                    ).then(
                        ({ marks }) => marks,
                        (): FigureMarkApi[] => {
                            cache.figureMarks = null
                            return []
                        }
                    )
                    return await cache.figureMarks
                },
            },
        ],
        keyClauses: [
            null as ReportKeyClausesApi | null,
            {
                loadKeyClauses: async (): Promise<ReportKeyClausesApi | null> => {
                    if (!values.asksJev || !values.fullReport || !values.page) {
                        return values.keyClauses
                    }
                    cache.keyClauses ??= todayReportsKeyClausesRetrieve(
                        String(values.currentProjectId),
                        props.reportId,
                        { include_impact: !!values.impactText }
                    ).catch((): null => {
                        cache.keyClauses = null
                        return null
                    })
                    return await cache.keyClauses
                },
            },
        ],
    })),
    reducers({
        reportFailed: [
            false,
            {
                loadFullReport: () => false,
                loadFullReportFailure: () => true,
                loadPage: () => false,
                loadPageFailure: () => true,
            },
        ],
        codeQuotes: [
            {} as Record<string, TodayCodeQuoteState>,
            {
                codeQuoteRead: (state, { signalId, quote }) => ({ ...state, [signalId]: quote }),
                codeQuoteCleared: (state, { signalId }) => {
                    const { [signalId]: _, ...rest } = state
                    return rest
                },
                codeQuotePicksCleared: (state) =>
                    Object.fromEntries(
                        Object.entries(state).map(([signalId, quote]) => [
                            signalId,
                            quote && quote !== 'loading' ? { ...quote, ...quote.candidates[0] } : quote,
                        ])
                    ),
            },
        ],
        expandedEvidence: [
            {} as Record<string, boolean>,
            {
                expandEvidence: (state, { signalId }) => ({ ...state, [signalId]: true }),
                collapseEvidence: (state, { signalId }) => ({ ...state, [signalId]: false }),
            },
        ],
        composerOpen: [false, { openComposer: () => true }],
        draft: [
            '',
            {
                setDraft: (_, { draft }) => draft,
                askAboutReport: () => '',
            },
        ],
    }),
    selectors(({ props }) => ({
        // The list row renders at once, and the full report replaces it when it arrives with its charts.
        // A failed load shows its error instead, so the page never passes off the list row as the report.
        currentReport: [
            (s) => [s.fullReport, s.reports, s.reportFailed],
            (fullReport: SignalReport | null, reports: SignalReport[], reportFailed: boolean): SignalReport | null =>
                reportFailed ? null : (fullReport ?? reports.find((report) => report.id === props.reportId) ?? null),
        ],
        lead: [(s) => [s.page], (page: ReportPageApi | null): string => page?.lead ?? ''],
        shownEvidence: [(s) => [s.page], (page: ReportPageApi | null): SignalViewApi[] => page?.evidence ?? []],
        evidenceCount: [(s) => [s.page], (page: ReportPageApi | null): number => page?.source_count ?? 0],
        lastSeen: [(s) => [s.page], (page: ReportPageApi | null): string | null => page?.last_seen ?? null],
        impactNumbers: [
            (s) => [s.currentReport, s.page],
            (currentReport: SignalReport | null, page: ReportPageApi | null): TodayImpactNumber[] =>
                currentReport ? impactNumbers(currentReport, page) : [],
        ],
        // A verdict given from Today shows before the report reloads.
        reportState: [
            (s) => [s.currentReport, s.reportStateOverrides],
            (
                currentReport: SignalReport | null,
                reportStateOverrides: Record<string, TodayReportState>
            ): TodayReportState =>
                reportStateOverrides[props.reportId] ?? (currentReport ? reportState(currentReport.status) : 'open'),
        ],
        isSample: [(_, p) => [p.reportId], (reportId: string): boolean => isSampleReportId(reportId)],
        asksJev: [
            (s) => [s.featureFlags, s.isSample],
            (featureFlags: FeatureFlagsSet, isSample: boolean): boolean =>
                !!featureFlags[FEATURE_FLAGS.TODAY_REPORT_JEV] && !isSample,
        ],
        proposal: [(s) => [s.page], (page: ReportPageApi | null): string => page?.proposal ?? ''],
        impactText: [
            (s) => [s.page, s.impactNumbers],
            (page: ReportPageApi | null, impactNumbers: TodayImpactNumber[]): string =>
                impactNumbers.length ? '' : (page?.impact_sentence ?? ''),
        ],
        shownFigureMarks: [
            (s) => [s.asksJev, s.figureMarks],
            (asksJev: boolean, figureMarks: FigureMarkApi[] | null): FigureMarkApi[] | null =>
                asksJev ? figureMarks : null,
        ],
        shownKeyClauses: [
            (s) => [s.asksJev, s.keyClauses],
            (asksJev: boolean, keyClauses: ReportKeyClausesApi | null): ReportKeyClausesApi | null =>
                asksJev ? keyClauses : null,
        ],
        leadMarks: [
            (s) => [s.lead, s.shownFigureMarks],
            (lead: string, figureMarks: FigureMarkApi[] | null): TodayMarkedFigure[] =>
                markedFigures(lead, marksIn(figureMarks, 'lead')),
        ],
        impactMarks: [
            (s) => [s.impactText, s.shownFigureMarks],
            (impactText: string, figureMarks: FigureMarkApi[] | null): TodayMarkedFigure[] =>
                markedFigures(impactText, marksIn(figureMarks, 'impact')),
        ],
        staleFiguresDate: [
            (s) => [s.leadMarks, s.impactMarks],
            (leadMarks: TodayMarkedFigure[], impactMarks: TodayMarkedFigure[]): string | null =>
                staleEvidenceDate([...leadMarks, ...impactMarks]),
        ],
        reportUrl: [
            (s) => [s.currentTeamId],
            (currentTeamId: number | null): string =>
                `${window.location.origin}${addProjectIdIfMissing(
                    urls.inboxReport('reports', props.reportId),
                    currentTeamId ?? undefined
                )}`,
        ],
    })),
    listeners(({ props, values, actions, cache }) => {
        const readFile = (file: CodeFileApi): Promise<RepositoryFileApi | null> => {
            if (values.isSample) {
                return Promise.resolve(null)
            }
            const key = `${file.repo}:${file.path}`
            cache.fileReads ??= new Map<string, Promise<RepositoryFileApi | null>>()
            if (!cache.fileReads.has(key)) {
                cache.fileReads.set(
                    key,
                    businessKnowledgeRepositoriesFileRetrieve(String(values.currentProjectId), file).catch(() => {
                        cache.fileReads.delete(key)
                        return null
                    })
                )
            }
            return cache.fileReads.get(key)
        }
        const captureOpen = ({ context, linkSource }: TodayPendingOpen, report: SignalReport): void => {
            if (values.isSample) {
                return
            }
            captureTodayReportOpened({
                report: signalReportSnapshot(report),
                openMethod: context ? 'click' : 'deeplink',
                linkSource,
                list: context?.list ?? null,
                rank: context?.rank ?? null,
                listSize: context?.listSize ?? null,
                source: context?.source ?? null,
            })
        }
        return {
            // A verdict that failed without an answer can still have saved, so the page reloads the report.
            [todayVerdictLogic.actionTypes.setReportVerdictFailure]: ({ reportId }: { reportId: string }) => {
                if (reportId === props.reportId) {
                    actions.loadFullReport()
                }
            },
            reportVisited: () => {
                // A visit with no click on Today is a deep-link: a shared URL, a PostHog AI link, a refresh,
                // or back / forward.
                const context = values.reportOpenContext
                const { pathname } = router.values.location
                const { link_source: linkSource, ...searchParams } = router.values.searchParams
                const onReportPage = reportIdFromPath(pathname) === props.reportId
                const open: TodayPendingOpen = {
                    context: context?.reportId === props.reportId ? context : null,
                    linkSource: onReportPage ? parseInboxReportLinkSource(linkSource) : null,
                }
                if (context) {
                    actions.setReportOpenContext(null)
                }
                if (onReportPage && linkSource !== undefined) {
                    // A copied address bar must not pass the original `link_source` on to the next reader.
                    router.actions.replace(pathname, searchParams, router.values.hashParams)
                }
                // A prefetched neighbor already has its report, so its open goes out now.
                if (values.fullReport && !values.fullReportLoading) {
                    captureOpen(open, values.fullReport)
                } else {
                    // A step away and back before the fetch ends is two visits, so each one keeps its own open.
                    cache.pendingOpens = [...(cache.pendingOpens ?? []), open]
                }
            },
            loadFullReportSuccess: ({ fullReport }) => {
                actions.loadKeyClauses()
                const opens: TodayPendingOpen[] = cache.pendingOpens ?? []
                cache.pendingOpens = []
                opens.forEach((open) => captureOpen(open, fullReport))
            },
            loadPageSuccess: () => {
                actions.loadKeyClauses()
                actions.loadFigureMarks()
            },
            [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
                actions.loadKeyClauses()
                actions.loadFigureMarks()
                if (!values.asksJev) {
                    actions.codeQuotePicksCleared()
                }
            },
            readCode: async ({ signal, files }) => {
                if (signal.signal_id in values.codeQuotes) {
                    return
                }
                actions.codeQuoteRead(signal.signal_id, 'loading')
                const reads = await Promise.all(files.map(readFile))
                const quote = findCodeQuote(files, reads, codeIdentifiers(signal.content))
                if (!quote && reads.includes(null)) {
                    actions.codeQuoteCleared(signal.signal_id)
                    return
                }
                if (!quote || quote.candidates.length < 2 || !values.asksJev) {
                    actions.codeQuoteRead(signal.signal_id, quote)
                    return
                }
                const choices = quote.candidates.slice(0, todayExcerptChoiceCreateBodyExcerptsMax)
                const excerpts = choices.map((candidate) =>
                    candidate.excerpt.lines.join('\n').slice(0, todayExcerptChoiceCreateBodyExcerptsItemMax)
                )
                const { index: pick } = await todayExcerptChoiceCreate(String(values.currentProjectId), {
                    finding: signal.content.slice(0, todayExcerptChoiceCreateBodyFindingMax),
                    excerpts,
                }).catch(() => ({ index: null }))
                const chosen = pick === null || !values.asksJev ? null : choices[pick]
                actions.codeQuoteRead(signal.signal_id, chosen ? { ...quote, ...chosen } : quote)
            },
            askAboutReport: ({ question }) => {
                const report = values.currentReport
                if (!report || !question || values.askingAi) {
                    return
                }
                captureInboxReportAction({
                    report,
                    actionType: 'discuss',
                    surface: 'today',
                    extra: discussQuestionProperties({ source: 'typed', suggestionCount: 0 }),
                })
                actions.askAi(question, 'report_page', report)
            },
            startWithPostHog: () => {
                const report = values.currentReport
                if (!report) {
                    return
                }
                if (reportWorkKind(report) === 'implement') {
                    captureInboxReportAction({
                        report,
                        actionType: 'create_pr',
                        surface: 'today',
                        extra: { has_feedback: false },
                    })
                    actions.createPrFromReport(report)
                    return
                }
                captureInboxReportAction({
                    report,
                    actionType: 'discuss',
                    surface: 'today',
                    extra: discussQuestionProperties({ source: 'preset', suggestionCount: 0 }),
                })
                actions.openReportDiscussion(report, values.reportUrl)
                actions.discussReport(
                    report,
                    values.reportUrl,
                    INVESTIGATE_QUESTION,
                    reportWorkPrompt(report, values.reportUrl)
                )
            },
            markOpened: ({ kind }) => {
                posthog.capture('today report mark opened', { report_id: props.reportId, kind })
            },
            evidenceOpened: ({ signal, destination }) => {
                posthog.capture('today report evidence opened', {
                    report_id: props.reportId,
                    source_product: signal.source_product,
                    source_type: signal.source_type,
                    destination,
                })
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadFullReport()
        actions.loadPage()
    }),
])
