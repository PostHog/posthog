export type TodayCodeQuoteState = TodayCodeQuote | null | 'loading'

function requestProjectId(): string {
    return String(
        teamLogic.values.currentTeamId ??
            getCurrentTeamIdOrNone() ??
            getProjectIdentifierInPath(window.location.pathname)
    )
}

function marksIn(figureMarks: FigureMarkApi[] | null, text: FigureTextEnumApi): FigureMarkApi[] {
    return (figureMarks ?? []).filter((mark) => mark.text === text)
}

