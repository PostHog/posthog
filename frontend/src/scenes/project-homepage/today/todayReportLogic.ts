import { MakeLogicType, afterMount, connect, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import { addProjectIdIfMissing } from 'lib/utils/kea-router'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { signalsReportsSignalsRetrieve } from 'products/signals/frontend/generated/api'
import { ReportChartApi, SignalNodeApi } from 'products/signals/frontend/generated/api.schemas'
import { SignalReport } from 'products/signals/frontend/inbox/types'
import { ChartPlacements, resolveChartPlacements } from 'products/signals/frontend/inbox/utils/chartPlacement'

import { todayLogic } from './todayLogic'
import { findSampleReport, isSampleReportId, sampleSignals } from './todaySampleReports'

export interface TodayReportLogicProps {
    reportId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayReportLogicValues {
    reports: SignalReport[] // todayLogic
    chartPlacements: ChartPlacements
    currentReport: SignalReport | null
    fullReport: SignalReport | null
    fullReportLoading: boolean
    reportFailed: boolean
    reportSignals: SignalNodeApi[] | null
    reportSignalsLoading: boolean
    reportUrl: string
    signals: SignalNodeApi[]
    trailingCharts: ReportChartApi[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayReportLogicActions {
    loadFullReport: () => any
    loadFullReportFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFullReportSuccess: (
        fullReport: SignalReport,
        payload?: any
    ) => {
        fullReport: SignalReport
        payload?: any
    }
    loadReportSignals: () => any
    loadReportSignalsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadReportSignalsSuccess: (
        reportSignals: SignalNodeApi[],
        payload?: any
    ) => {
        reportSignals: SignalNodeApi[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayReportLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        currentReport: (
            fullReport: SignalReport | null,
            reports: SignalReport[],
            reportFailed: boolean
        ) => SignalReport | null
        chartPlacements: (currentReport: SignalReport | null) => ChartPlacements
        trailingCharts: (currentReport: SignalReport | null, chartPlacements: ChartPlacements) => ReportChartApi[]
        signals: (reportSignals: SignalNodeApi[] | null) => SignalNodeApi[]
    }
}

export type todayReportLogicType = MakeLogicType<
    todayReportLogicValues,
    todayReportLogicActions,
    TodayReportLogicProps,
    todayReportLogicMeta
>

export const todayReportLogic = kea<todayReportLogicType>([
    props({} as TodayReportLogicProps),
    key((props) => props.reportId),
    path((reportId) => ['scenes', 'project-homepage', 'today', 'todayReportLogic', reportId]),
    connect(() => ({ values: [todayLogic, ['reports']] })),
    loaders(({ props }) => ({
        fullReport: [
            null as SignalReport | null,
            {
                loadFullReport: async () => {
                    if (isSampleReportId(props.reportId)) {
                        const report = findSampleReport(props.reportId)
                        if (!report) {
                            throw new Error('Sample report not found')
                        }
                        return report
                    }
                    // nosemgrep: prefer-codegen-api-namespaced-signals -- Today passes reports to the Inbox's helpers, which take the handwritten SignalReport. The generated report type is wider (string status and priority, read-only arrays), so this call moves to generated types together with the Inbox.
                    return await api.signalReports.get(props.reportId)
                },
            },
        ],
        reportSignals: [
            null as SignalNodeApi[] | null,
            {
                loadReportSignals: async (): Promise<SignalNodeApi[]> => {
                    if (isSampleReportId(props.reportId)) {
                        return sampleSignals(props.reportId)
                    }
                    const response = await signalsReportsSignalsRetrieve(
                        String(teamLogic.values.currentTeamId),
                        props.reportId
                    )
                    return response.signals
                },
            },
        ],
    })),
    reducers({
        reportFailed: [false, { loadFullReport: () => false, loadFullReportFailure: () => true }],
    }),
    selectors(({ props }) => ({
        // The list row renders at once, and the full report replaces it when it arrives with its charts.
        // A failed load shows its error instead, so the page never passes off the list row as the report.
        currentReport: [
            (s) => [s.fullReport, s.reports, s.reportFailed],
            (fullReport: SignalReport | null, reports: SignalReport[], reportFailed: boolean): SignalReport | null =>
                reportFailed ? null : (fullReport ?? reports.find((report) => report.id === props.reportId) ?? null),
        ],
        chartPlacements: [
            (s) => [s.currentReport],
            (currentReport: SignalReport | null): ChartPlacements =>
                resolveChartPlacements(
                    currentReport?.summary,
                    (currentReport?.charts ?? []).map((chart) => chart.chart_id)
                ),
        ],
        trailingCharts: [
            (s) => [s.currentReport, s.chartPlacements],
            (currentReport: SignalReport | null, chartPlacements: ChartPlacements): ReportChartApi[] =>
                (currentReport?.charts ?? []).filter((chart) => !chartPlacements.inlineIds.has(chart.chart_id)),
        ],
        // The API returns signals oldest first, and the newest one is the most useful to read first.
        signals: [
            (s) => [s.reportSignals],
            (reportSignals: SignalNodeApi[] | null): SignalNodeApi[] =>
                [...(reportSignals ?? [])].sort(
                    (first, second) => new Date(second.timestamp).getTime() - new Date(first.timestamp).getTime()
                ),
        ],
        // Absolute, because the session prompt gives it to the agent so the agent can read the report.
        reportUrl: [
            () => [],
            (): string =>
                `${window.location.origin}${addProjectIdIfMissing(urls.inboxReport('reports', props.reportId))}`,
        ],
    })),
    afterMount(({ actions }) => {
        actions.loadFullReport()
        actions.loadReportSignals()
    }),
])
