import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { inviteLogic } from 'lib/logic/inviteLogic'
import { organizationLogic } from 'scenes/organizationLogic'
import { PersonalGitHubIntegration, personalIntegrationsLogic } from 'scenes/settings/user/personalIntegrationsLogic'
import { teamLogic } from 'scenes/teamLogic'

import { OrganizationType } from '~/types'

import { todayLogic } from './todayLogic'

export type TodayGetStartedStepKey = 'install' | 'github' | 'invite'

export interface TodayGetStartedStep {
    key: TodayGetStartedStepKey
    done: boolean
    skipped: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayGetStartedLogicValues {
    currentOrganization: OrganizationType | null // organizationLogic
    currentTeamId: number | null // teamLogic
    integrations: PersonalGitHubIntegration[] // personalIntegrationsLogic
    integrationsLoading: boolean // personalIntegrationsLogic
    isNewProject: boolean // todayLogic
    hiddenForTeams: Record<string, true>
    githubDismissedForTeams: Record<string, true>
    githubDismissed: boolean
    githubConnected: boolean
    aiEnabled: boolean
    guideOpen: boolean
    hidden: boolean
    stepsReady: boolean
    steps: TodayGetStartedStep[]
    doneCount: number
    allDone: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface todayGetStartedLogicActions {
    connectGitHub: () => { value: true } // personalIntegrationsLogic
    showInviteModal: () => { value: true } // inviteLogic
    hideGuide: () => {
        value: true
    }
    openGuide: () => {
        value: true
    }
    closeGuide: () => {
        value: true
    }
    dismissGitHub: () => {
        value: true
    }
    dismissGitHubForTeam: (teamId: number | null) => {
        teamId: number | null
    }
    hideGuideForTeam: (teamId: number | null) => {
        teamId: number | null
    }
    stepActed: (
        step: TodayGetStartedStepKey,
        action: string
    ) => {
        action: string
        step: TodayGetStartedStepKey
    }
}

export type todayGetStartedLogicType = MakeLogicType<todayGetStartedLogicValues, todayGetStartedLogicActions>

export const todayGetStartedLogic = kea<todayGetStartedLogicType>([
    path(['scenes', 'project-homepage', 'today', 'todayGetStartedLogic']),
    connect(() => ({
        values: [
            organizationLogic,
            ['currentOrganization'],
            personalIntegrationsLogic,
            ['integrations', 'integrationsLoading'],
            todayLogic,
            ['isNewProject'],
            teamLogic,
            ['currentTeamId'],
        ],
        actions: [personalIntegrationsLogic, ['connectGitHub'], inviteLogic, ['showInviteModal']],
    })),
    actions({
        hideGuide: true,
        openGuide: true,
        closeGuide: true,
        hideGuideForTeam: (teamId: number | null) => ({ teamId }),
        dismissGitHub: true,
        dismissGitHubForTeam: (teamId: number | null) => ({ teamId }),
        stepActed: (step: TodayGetStartedStepKey, action: string) => ({ step, action }),
    }),
    reducers({
        // pinned: localStorage key via the logic path and reducer name, renaming resets users' choice
        hiddenForTeams: [
            {} as Record<string, true>,
            { persist: true },
            { hideGuideForTeam: (state, { teamId }) => ({ ...state, [String(teamId)]: true }) },
        ],
        // pinned: localStorage key via the logic path and reducer name, renaming resets users' choice
        githubDismissedForTeams: [
            {} as Record<string, true>,
            { persist: true },
            { dismissGitHubForTeam: (state, { teamId }) => ({ ...state, [String(teamId)]: true }) },
        ],
        guideOpen: [false, { openGuide: () => true, closeGuide: () => false, hideGuide: () => false }],
    }),
    selectors({
        hidden: [
            (s) => [s.hiddenForTeams, s.currentTeamId],
            (hiddenForTeams: Record<string, true>, currentTeamId: number | null): boolean =>
                !!hiddenForTeams[String(currentTeamId)],
        ],
        githubDismissed: [
            (s) => [s.githubDismissedForTeams, s.currentTeamId],
            (githubDismissedForTeams: Record<string, true>, currentTeamId: number | null): boolean =>
                !!githubDismissedForTeams[String(currentTeamId)],
        ],
        aiEnabled: [
            (s) => [s.currentOrganization],
            (currentOrganization: OrganizationType | null): boolean =>
                !!currentOrganization?.is_ai_data_processing_approved,
        ],
        githubConnected: [
            (s) => [s.integrations],
            (integrations: PersonalGitHubIntegration[]): boolean => integrations.length > 0,
        ],
        stepsReady: [
            (s) => [s.integrationsLoading, s.currentOrganization],
            (integrationsLoading: boolean, currentOrganization: OrganizationType | null): boolean =>
                !integrationsLoading && !!currentOrganization,
        ],
        steps: [
            (s) => [s.isNewProject, s.githubConnected, s.githubDismissed, s.aiEnabled, s.currentOrganization],
            (
                isNewProject: boolean,
                githubConnected: boolean,
                githubDismissed: boolean,
                aiEnabled: boolean,
                currentOrganization: OrganizationType | null
            ): TodayGetStartedStep[] => [
                { key: 'install', done: !isNewProject, skipped: false },
                ...(aiEnabled
                    ? [{ key: 'github' as const, done: githubConnected, skipped: !githubConnected && githubDismissed }]
                    : []),
                { key: 'invite', done: (currentOrganization?.member_count ?? 0) > 1, skipped: false },
            ],
        ],
        doneCount: [
            (s) => [s.steps],
            (steps: TodayGetStartedStep[]): number => steps.filter((step) => step.done || step.skipped).length,
        ],
        allDone: [
            (s) => [s.steps],
            (steps: TodayGetStartedStep[]): boolean => steps.every((step) => step.done || step.skipped),
        ],
    }),
    listeners(({ actions, values }) => ({
        openGuide: () => {
            posthog.capture('today get started opened', { done_count: values.doneCount })
        },
        dismissGitHub: () => {
            posthog.capture('today github dismissed')
            actions.dismissGitHubForTeam(values.currentTeamId)
        },
        hideGuide: () => {
            posthog.capture('today get started hidden', { done_count: values.doneCount })
            actions.hideGuideForTeam(values.currentTeamId)
        },
        stepActed: ({ step, action }) => {
            posthog.capture('today get started step clicked', {
                step,
                action,
                done_count: values.doneCount,
            })
            if (action === 'skip') {
                actions.dismissGitHub()
            } else if (action === 'connect') {
                actions.connectGitHub()
            } else if (action === 'invite') {
                actions.showInviteModal()
            }
        },
    })),
])
