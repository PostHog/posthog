export const todayNewsLogic = kea<todayNewsLogicType>([
    path(['scenes', 'project-homepage', 'today', 'todayNewsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
        actions: [
            attachedContextLogic,
            ['pickItem', 'removePickedItem'],
            todayHomeComposerLogic,
            ['prefill', 'homeTaskStarted'],
        ],
    })),
    actions({
        openNews: true,
        closeNews: true,
        diveIn: (story: NewsStoryApi, position: number) => ({ story, position }),
        rateStory: (story: TodayNewsRatedStory, rating: TodayNewsRating) => ({ story, rating }),
        markEditionRead: (projectId: string, editionId: string) => ({ projectId, editionId }),
    }),
    loaders(({ values }) => ({
        news: [
            null as TodayNewsApi | null,
            {
                loadNews: async (): Promise<TodayNewsApi | null> => {
                    if (values.currentProjectId === null) {
                        return null
                    }
                    try {
                        return await todayNewsRetrieve(String(values.currentProjectId))
                    } catch (error) {
                        if (error instanceof ApiError && error.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
                writeNews: async (): Promise<TodayNewsApi | null> => {
                    if (values.currentProjectId === null) {
                        return values.news
                    }
                    return await todayNewsWriteCreate(String(values.currentProjectId))
                },
            },
        ],
    })),
    reducers({
        news: {
            writeNews: (news) => (news ? { ...news, status: 'computing' } : news),
            writeNewsFailure: (news) => (news ? { ...news, status: 'failed' } : news),
        },
        writingSince: [
            null as string | null,
            {
                writeNews: (state) => state ?? dayjs().toISOString(),
                writeNewsFailure: () => null,
                loadNewsSuccess: (state, { news }) => writingSinceAfter(state, news),
                writeNewsSuccess: (state, { news }) => writingSinceAfter(state, news),
            },
        ],
        isWriteUnavailable: [
            false,
            {
                writeNews: () => false,
                writeNewsSuccess: (_, { news }) => news?.status === 'not_started',
                loadNewsSuccess: (state, { news }) => state && news?.status === 'not_started',
            },
        ],
        isNewsOpen: [
            false,
            {
                openNews: () => true,
                closeNews: () => false,
                diveIn: () => false,
            },
        ],
        readEditionIds: [
            {} as Record<string, string>,
            { persist: true },
            {
                markEditionRead: (state, { projectId, editionId }) => ({ ...state, [projectId]: editionId }),
            },
        ],
        storyRatings: [
            {} as Record<string, TodayNewsRating>,
            { persist: true },
            {
                rateStory: (state, { story, rating }) => {
                    const { [story.key]: previous, ...rest } = state
                    return previous === rating ? rest : { ...rest, [story.key]: rating }
                },
            },
        ],
    }),
    selectors({
        edition: [(s) => [s.news], (news: TodayNewsApi | null): NewsEditionApi | null => news?.edition ?? null],
        newsStatus: [(s) => [s.news], (news: TodayNewsApi | null): NewsStatusEnumApi | null => news?.status ?? null],
        canOpenNews: [
            (s) => [s.newsStatus, s.edition],
            (newsStatus: NewsStatusEnumApi | null, edition: NewsEditionApi | null): boolean =>
                !!edition || newsStatus === 'not_started' || newsStatus === 'computing',
        ],
        showsNewsDialog: [
            (s) => [s.canOpenNews, s.isNewsOpen],
            (canOpenNews: boolean, isNewsOpen: boolean): boolean => canOpenNews || isNewsOpen,
        ],
        hasUnreadNews: [
            (s) => [s.readEditionIds, s.currentProjectId, s.newsStatus, s.edition],
            (
                readEditionIds: Record<string, string>,
                currentProjectId: number | string,
                newsStatus: NewsStatusEnumApi | null,
                edition: NewsEditionApi | null
            ): boolean =>
                newsStatus === 'not_started' || (!!edition && readEditionIds[String(currentProjectId)] !== edition.id),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const scheduleLoad = (delay: number): void => {
            const due = Date.now() + delay
            cache.disposables.add(() => {
                const poll = window.setTimeout(() => actions.loadNews(), Math.max(0, due - Date.now()))
                return () => clearTimeout(poll)
            }, 'newsPoll')
        }
        const markShownEditionRead = (news: TodayNewsApi | null): void => {
            if (values.isNewsOpen && news?.edition) {
                actions.markEditionRead(String(values.currentProjectId), news.edition.id)
            }
        }
        return {
            loadNewsSuccess: ({ news }) => {
                const edition = news?.edition
                if (edition && cache.shownEditionId !== edition.id) {
                    cache.shownEditionId = edition.id
                    posthog.capture('today news shown', {
                        edition_id: edition.id,
                        unread: values.hasUnreadNews,
                        stories: 1 + edition.stories.length,
                        briefs: edition.briefs.length,
                    })
                }
                markShownEditionRead(news)
                if (news?.status === 'failed') {
                    cache.writeRequestedFor = null
                }
                scheduleLoad(nextLoadDelay(news))
            },
            writeNewsSuccess: ({ news }) => {
                markShownEditionRead(news)
                if (news?.status && WRITABLE_STATUSES.includes(news.status)) {
                    cache.writeRequestedFor = null
                }
                scheduleLoad(nextLoadDelay(news))
            },
            loadNewsFailure: () => {
                scheduleLoad(NEWS_REFRESH_MS)
            },
            writeNewsFailure: () => {
                cache.writeRequestedFor = null
                scheduleLoad(NEWS_REFRESH_MS)
            },
            openNews: () => {
                const { edition, newsStatus } = values
                const projectId = String(values.currentProjectId)
                posthog.capture('today news opened', {
                    edition_id: edition?.id ?? null,
                    had_unread: values.hasUnreadNews,
                })
                if (edition) {
                    actions.markEditionRead(projectId, edition.id)
                }
                const writeKey = `${projectId}:${dayjs().format('YYYY-MM-DD')}`
                if (newsStatus && WRITABLE_STATUSES.includes(newsStatus) && cache.writeRequestedFor !== writeKey) {
                    cache.writeRequestedFor = writeKey
                    actions.writeNews()
                }
            },
            diveIn: ({ story, position }) => {
                cache.divedStoryId = story.id
                posthog.capture('today news dive in', {
                    edition_id: values.edition?.id,
                    story_id: story.id,
                    product: story.product,
                    position,
                })
                const attachment: AttachedContextItem = {
                    type: 'text',
                    label: 'News story',
                    value: `${story.title}. ${story.summary}`,
                }
                if (cache.divedAttachmentKey) {
                    actions.removePickedItem(cache.divedAttachmentKey)
                }
                actions.pickItem(attachment)
                cache.divedAttachmentKey = attachedContextItemKey(attachment)
                actions.prefill(story.dive_prompt)
            },
            rateStory: ({ story, rating }) => {
                posthog.capture('today news story rated', {
                    edition_id: values.edition?.id,
                    story_id: story.id,
                    part: story.part,
                    product: story.product,
                    position: story.position,
                    rating: values.storyRatings[story.key] ? rating : 'cleared',
                })
            },
            homeTaskStarted: () => {
                cache.divedAttachmentKey = null
                if (cache.divedStoryId) {
                    posthog.capture('today news task started', {
                        edition_id: values.edition?.id,
                        story_id: cache.divedStoryId,
                    })
                    cache.divedStoryId = null
                }
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadNews()
    }),
])
