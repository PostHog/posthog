export type todayNewsLogicType = MakeLogicType<
    todayNewsLogicValues,
    todayNewsLogicActions,
    Record<string, any>,
    todayNewsLogicMeta
>

export const todayNewsLogic = kea<todayNewsLogicType>([
    path(['scenes', 'project-homepage', 'today', 'todayNewsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
        actions: [attachedContextLogic, ['pickItem']],
    })),
    actions({
        openNews: true,
        closeNews: true,
        diveIn: (story: NewsStoryApi, position: number) => ({ story, position }),
        markEditionRead: (projectId: string, editionId: string) => ({ projectId, editionId }),
        homeTaskStarted: (taskId: string) => ({ taskId }),
    }),
    loaders(({ values }) => ({
        news: [
            null as TodayNewsApi | null,
            {
                loadNews: async (): Promise<TodayNewsApi | null> => {
                    if (values.currentProjectId === null) {
                        return null
                    }
                    try {
                        return await todayNewsRetrieve(String(values.currentProjectId))
                    } catch (error) {
                        if (error instanceof ApiError && error.status === 404) {
                            return null
                        }
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        isNewsOpen: [
            false,
            {
                openNews: () => true,
                closeNews: () => false,
                diveIn: () => false,
            },
        ],
        readEditionIds: [
            {} as Record<string, string>,
            { persist: true },
            {
                markEditionRead: (state, { projectId, editionId }) => ({ ...state, [projectId]: editionId }),
            },
        ],
        composerPrefill: [
            null as ComposerPrefillRequest | null,
            {
                diveIn: (_, { story }) => ({ prompt: story.dive_prompt }),
            },
        ],
        composerFocusRequest: [
            0,
            {
                diveIn: (state) => state + 1,
            },
        ],
        divedStoryId: [
            null as string | null,
            {
                diveIn: (_, { story }) => story.id,
            },
        ],
    }),
    selectors({
        edition: [(s) => [s.news], (news: TodayNewsApi | null): NewsEditionApi | null => news?.edition ?? null],
        hasUnreadNews: [
            (s) => [s.readEditionIds, s.currentProjectId, s.edition],
            (
                readEditionIds: Record<string, string>,
                currentProjectId: number | string,
                edition: NewsEditionApi | null
            ): boolean => !!edition && readEditionIds[String(currentProjectId)] !== edition.id,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        loadNewsSuccess: ({ news }) => {
            const edition = news?.edition
            if (edition && cache.shownEditionId !== edition.id) {
                cache.shownEditionId = edition.id
                posthog.capture('today news shown', {
                    edition_id: edition.id,
                    unread: values.hasUnreadNews,
                    stories: 1 + edition.stories.length,
                    briefs: edition.briefs.length,
                })
            }
            if (news?.status === 'computing') {
                cache.disposables.add(() => {
                    const poll = window.setTimeout(() => actions.loadNews(), NEWS_POLL_MS)
                    return () => clearTimeout(poll)
                }, 'newsPoll')
            }
        },
        openNews: () => {
            const { edition } = values
            if (!edition) {
                return
            }
            posthog.capture('today news opened', { edition_id: edition.id, had_unread: values.hasUnreadNews })
            actions.markEditionRead(String(values.currentProjectId), edition.id)
        },
        diveIn: ({ story, position }) => {
            posthog.capture('today news dive in', {
                edition_id: values.edition?.id,
                story_id: story.id,
                product: story.product,
                position,
            })
            actions.pickItem({
                type: 'text',
                key: `today-news-${story.id}`,
                label: story.title,
                value: `${story.title}. ${story.summary}`,
            })
        },
        homeTaskStarted: ({ taskId }) => {
            posthog.capture('today home task started', { from_news_story_id: values.divedStoryId })
            router.actions.push(urls.aiTask(taskId))
        },
    })),
    afterMount(({ actions }) => {
        actions.loadNews()
    }),
])
