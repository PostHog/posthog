export const NEWS_POLL_MS = 5_000
export const NEWS_REFRESH_MS = 60 * 60 * 1000

const WRITABLE_STATUSES: NewsStatusEnumApi[] = ['not_started', 'failed']

function nextLoadDelay(news: TodayNewsApi | null): number {
    return news?.status === 'computing' ? NEWS_POLL_MS : NEWS_REFRESH_MS
}

function writingSinceAfter(state: string | null, news: TodayNewsApi | null): string | null {
    return news?.status === 'computing' ? (state ?? dayjs().toISOString()) : null
}

