import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { ApiError } from 'lib/api'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { attachedContextLogic } from '~/layout/ai/attachedContextLogic'

import type { ComposerPrefillRequest } from 'products/posthog_ai/frontend/api/runner'
import { todayNewsRetrieve } from 'products/today/frontend/generated/api'
import type { NewsEditionApi, NewsStoryApi, TodayNewsApi } from 'products/today/frontend/generated/api.schemas'

