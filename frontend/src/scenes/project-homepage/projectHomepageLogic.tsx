import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router, urlToAction } from 'kea-router'

import api from 'lib/api'
import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { MaxContextInput } from 'scenes/max/maxTypes'
import { projectLogic } from 'scenes/projectLogic'
import { urls } from 'scenes/urls'

import { getQueryBasedInsightModel } from '~/queries/nodes/InsightViz/utils'
import { Breadcrumb, InsightModel } from '~/types'

import type { Node } from '../../queries/schema/schema-general'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface projectHomepageLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentProjectId: number | null // projectLogic
    breadcrumbs: Breadcrumb[]
    expandedInsightIds: Set<string>
    maxContext: MaxContextInput[]
    recentInsights: InsightModel[]
    recentInsightsLoading: boolean
    todayHomeEnabled: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface projectHomepageLogicActions {
    loadRecentInsights: () => any
    loadRecentInsightsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRecentInsightsSuccess: (
        recentInsights: InsightModel<Node<Record<string, any>>>[],
        payload?: any
    ) => {
        recentInsights: InsightModel<Node<Record<string, any>>>[]
        payload?: any
    }
    toggleInsightExpanded: (insightShortId: string) => {
        insightShortId: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface projectHomepageLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        todayHomeEnabled: (featureFlags: FeatureFlagsSet) => boolean
    }
}

export type projectHomepageLogicType = MakeLogicType<
    projectHomepageLogicValues,
    projectHomepageLogicActions,
    Record<string, any>,
    projectHomepageLogicMeta
>

export const projectHomepageLogic = kea<projectHomepageLogicType>([
    path(['scenes', 'project-homepage', 'projectHomepageLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']],
    })),

    actions({
        toggleInsightExpanded: (insightShortId: string) => ({ insightShortId }),
    }),

    reducers({
        expandedInsightIds: [
            new Set<string>(),
            {
                toggleInsightExpanded: (state, { insightShortId }) => {
                    const next = new Set(state)
                    next.has(insightShortId) ? next.delete(insightShortId) : next.add(insightShortId)
                    return next
                },
            },
        ],
    }),

    loaders(({ values }) => ({
        recentInsights: [
            [] as InsightModel[],
            {
                loadRecentInsights: async () => {
                    // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. insightsMyLastViewedRetrieve() from 'products/product_analytics/frontend/generated/api' serves this route, but its generated types do not describe this call yet, so fix the endpoint's OpenAPI schema first.
                    const insights = await api.get<InsightModel[]>(
                        `api/projects/${values.currentProjectId}/insights/my_last_viewed`
                    )
                    return insights.map((legacyInsight) => getQueryBasedInsightModel(legacyInsight))
                },
            },
        ],
    })),

    selectors({
        // Matches the condition that swaps in the Today rail, because Today has no way around without it.
        todayHomeEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV],
        ],
        maxContext: [
            () => [],
            // Context is only added explicitly via the @Context button.
            (): MaxContextInput[] => [],
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: 'home',
                    name: 'Home',
                    iconType: 'home',
                },
            ],
        ],
    }),

    urlToAction(({ values }) => ({
        // A Today report link opened where Today is off lands on the same report in the Inbox.
        [urls.todayReport(':reportId')]: ({ reportId }) => {
            if (reportId && !values.todayHomeEnabled) {
                router.actions.replace(urls.inboxReport('reports', reportId))
            }
        },
    })),
])
