export type HomepageMode = 'idle' | 'search' | 'ai'
export type AnimationPhase = 'idle' | 'moving' | 'separator' | 'content'

export interface LayoutState {
    mode: HomepageMode
    animationPhase: AnimationPhase
}

export type HomepageGridItemKind = 'dashboard' | 'recent' | 'suggestion'

export interface HomepageGridItem {
    id: string
    label: string
    /** Caption under the label on suggestion cards, naming what the suggestion is about. */
    description?: string
    icon?: React.ReactNode
    href?: string
    kind: HomepageGridItemKind
    itemType?: string | null
    /** Prompt submitted to PostHog AI when a suggestion is activated. */
    prompt?: string
    /** Conversation opened when a continue-conversation suggestion is activated. */
    conversationId?: string
    /** When set, activation types `prompt` into the input and waits for the user to complete it. */
    fillInHint?: string
    /** Where a suggestion came from, captured on click so the sources can be compared. */
    source?: 'continue' | 'recent' | 'static' | 'topic'
}

// The rail shares a fixed row budget between pinned dashboards and recents, so it cannot
// outgrow the suggestions list next to it: recents expand into whatever pinned doesn't use.
export const RAIL_ROW_BUDGET = 6
export const PINNED_DASHBOARDS_LIMIT = 4

// The suggestion typewriter runs faster than the shared human-pace curve: on the homepage the
// prompt is already fully visible on the card, so the animation is a cue, not a reveal.
const TYPING_SPEEDUP_FACTOR = 0.7

const PREVIOUS_HOMEPAGE_KEY = 'ai-first-previous-homepage'

function getStorageKey(): string {
    const teamId = teamLogic.findMounted()?.values.currentTeamId ?? 'null'
    return `${PREVIOUS_HOMEPAGE_KEY}-${teamId}`
}

function loadPreviousHomepage(): SceneTab | null {
    try {
        const stored = localStorage.getItem(getStorageKey())
        return stored ? JSON.parse(stored) : null
    } catch {
        return null
    }
}

function savePreviousHomepage(tab: SceneTab | null): void {
    const key = getStorageKey()
    if (tab) {
        localStorage.setItem(key, JSON.stringify(tab))
    } else {
        localStorage.removeItem(key)
    }
}

// pinned: analytics event name and property names; renaming breaks dashboards
function reportGridItemClicked(item: HomepageGridItem): void {
    posthog.capture('homepage grid item clicked', {
        kind: item.kind,
        href: item.href,
        prompt: item.prompt,
        source: item.source,
    })
}

