/**
 * The analytics items and collections a person pinned. Pins are the project tree's shortcuts, which the
 * classic navigation lists as Starred, so a pin made here shows in every other place that lists them, and the reverse.
 */
export const analyticsPinnedLogic = kea<analyticsPinnedLogicType>([
    path(['scenes', 'analytics', 'analyticsPinnedLogic']),
    connect(() => ({
        values: [projectTreeDataLogic, ['shortcutData', 'shortcutDataLoading']],
        actions: [projectTreeDataLogic, ['addShortcutItem', 'deleteShortcut', 'reorderShortcuts']],
    })),
    actions({
        movePinned: (shortcutId: string, overShortcutId: string) => ({ shortcutId, overShortcutId }),
        togglePinned: (target: PinTarget) => ({ target }),
        setRecentlyPinned: (key: string) => ({ key }),
        clearRecentlyPinned: true,
    }),
    reducers({
        // The pin the sidebar animates in once, so a person sees where the new pin went.
        recentlyPinnedKey: [
            null as string | null,
            {
                setRecentlyPinned: (_, { key }) => key,
                clearRecentlyPinned: () => null,
            },
        ],
    }),
    selectors({
        pinnedAnalytics: [
            (s) => [s.shortcutData],
            (shortcutData: FileSystemEntry[]): PinnedAnalytics[] =>
                shortcutData.flatMap((shortcut): PinnedAnalytics[] => {
                    if (!shortcut.id || !shortcut.ref) {
                        return []
                    }
                    // A folder shortcut's `path` is its display name; `ref` holds the folder it points at.
                    if (shortcut.type === 'folder') {
                        return isSpacePath(shortcut.ref)
                            ? [
                                  {
                                      kind: 'collection',
                                      key: pinKey('folder', shortcut.ref),
                                      shortcutId: shortcut.id,
                                      path: shortcut.ref,
                                      name: fileSystemEntryName({ path: shortcut.ref }),
                                  },
                              ]
                            : []
                    }
                    const item = fileSystemEntryToAnalytics(shortcut)
                    return item
                        ? [{ kind: 'item', key: pinKey(item.type, item.id), shortcutId: shortcut.id, item }]
                        : []
                }),
        ],
        pinnedShortcutIds: [
            (s) => [s.pinnedAnalytics],
            (pinnedAnalytics: PinnedAnalytics[]): Map<string, string> =>
                new Map(pinnedAnalytics.map((pinned) => [pinned.key, pinned.shortcutId])),
        ],
        pinnedCollectionPaths: [
            (s) => [s.pinnedAnalytics],
            (pinnedAnalytics: PinnedAnalytics[]): Set<string> =>
                new Set(pinnedAnalytics.flatMap((pinned) => (pinned.kind === 'collection' ? [pinned.path] : []))),
        ],
    }),
    listeners(({ actions, values }) => ({
        movePinned: ({ shortcutId, overShortcutId }) => {
            // Pins are a subset of all shortcuts, so the move happens in the full list to keep the others in place.
            const ids = values.shortcutData.map((shortcut) => shortcut.id).filter((id): id is string => !!id)
            const from = ids.indexOf(shortcutId)
            const to = ids.indexOf(overShortcutId)
            if (from < 0 || to < 0 || from === to) {
                return
            }
            ids.splice(to, 0, ...ids.splice(from, 1))
            actions.reorderShortcuts(ids)
        },
        togglePinned: ({ target }) => {
            // Every pin control is disabled while a change saves. This also stops a repeated dispatch.
            if (values.shortcutDataLoading) {
                return
            }
            const shortcutId = values.pinnedShortcutIds.get(pinKey(target.type, target.ref))
            if (shortcutId) {
                actions.deleteShortcut(shortcutId, 'Unpinned from sidebar')
                return
            }
            actions.setRecentlyPinned(pinKey(target.type, target.ref))
            if (target.type === 'folder') {
                // A folder shortcut keeps its path as ref, so a rename moves the pin with the folder.
                actions.addShortcutItem({ path: target.ref, type: 'folder' } as FileSystemEntry, 'Pinned to sidebar')
            } else {
                actions.addShortcutItem(
                    {
                        path: escapePath(target.name),
                        type: target.type,
                        ref: target.ref,
                        href: target.href,
                    } as FileSystemEntry,
                    'Pinned to sidebar'
                )
            }
        },
    })),
])
