/** The analytics items and collections among the sidebar pins, for the Analytics pane's Pinned section. */
export const analyticsPinnedLogic = kea<analyticsPinnedLogicType>([
    path(['scenes', 'analytics', 'analyticsPinnedLogic']),
    connect(() => ({
        values: [sidebarPinsLogic, ['shortcutData']],
        actions: [projectTreeDataLogic, ['addShortcutItem'], router, ['locationChanged']],
    })),
    actions({
        showPinHint: true,
        hidePinHint: true,
    }),
    loaders({
        hasAnalyticsItems: [
            null as boolean | null,
            {
                loadHasAnalyticsItems: async (_: void, breakpoint) => {
                    const pages = await Promise.all(
                        ANALYTICS_TYPES.map(({ type }) =>
                            api.fileSystem.list({ ...fileSystemTypeParams(type), limit: 1 })
                        )
                    )
                    breakpoint()
                    return pages.some((page) => page.results.length > 0)
                },
            },
        ],
    }),
    reducers({
        // The hint on the list's first row menu, which shows where to pin an item from.
        pinHintVisible: [
            false,
            {
                showPinHint: () => true,
                hidePinHint: () => false,
                addShortcutItem: () => false,
            },
        ],
    }),
    selectors({
        pinnedAnalytics: [
            (s) => [s.shortcutData],
            (shortcutData: FileSystemEntry[]): PinnedAnalytics[] =>
                shortcutData.flatMap((shortcut): PinnedAnalytics[] => {
                    if (!shortcut.id || !shortcut.ref) {
                        return []
                    }
                    // A folder shortcut's `path` is its display name; `ref` holds the folder it points at.
                    if (shortcut.type === 'folder') {
                        return isSpacePath(shortcut.ref)
                            ? [
                                  {
                                      kind: 'collection',
                                      key: pinKey('folder', shortcut.ref),
                                      shortcutId: shortcut.id,
                                      path: shortcut.ref,
                                      name: fileSystemEntryName({ path: shortcut.ref }),
                                  },
                              ]
                            : []
                    }
                    const item = fileSystemEntryToAnalytics(shortcut)
                    return item
                        ? [{ kind: 'item', key: pinKey(item.type, item.id), shortcutId: shortcut.id, item }]
                        : []
                }),
        ],
        pinnedCollectionPaths: [
            (s) => [s.pinnedAnalytics],
            (pinnedAnalytics: PinnedAnalytics[]): Set<string> =>
                new Set(pinnedAnalytics.flatMap((pinned) => (pinned.kind === 'collection' ? [pinned.path] : []))),
        ],
    }),
    listeners(({ actions, values }) => ({
        // Creating a first item navigates to it. Once there is one, the answer stays yes for the visit.
        locationChanged: () => {
            if (values.hasAnalyticsItems === false && !values.hasAnalyticsItemsLoading) {
                actions.loadHasAnalyticsItems()
            }
        },
        showPinHint: () => {
            // pinned: analytics event name. Renaming it breaks dashboards.
            posthog.capture('analytics pin hint shown')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadHasAnalyticsItems()
    }),
])
