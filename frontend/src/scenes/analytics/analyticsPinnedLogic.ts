export interface PinTarget {
    type: string
    ref: string
    name: string
    href?: string
}

export type PinnedAnalytics =
    | { kind: 'item'; key: string; shortcutId: string; item: AnalyticsItem }
    | { kind: 'collection'; key: string; shortcutId: string; path: string; name: string }

/** One key per pinnable thing. `insight/trends` and `insight` share a key, since the shortcut keeps whichever it was given. */
export function pinKey(type: string, ref: string): string {
    return `${fileSystemBaseType(type)}:${ref}`
}

