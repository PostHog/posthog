/** The analytics items and collections among the sidebar pins, for the Analytics pane's Pinned section. */
export const analyticsPinnedLogic = kea<analyticsPinnedLogicType>([
    path(['scenes', 'analytics', 'analyticsPinnedLogic']),
    connect(() => ({
        values: [sidebarPinsLogic, ['shortcutData', 'shortcutDataLoading'], uiCustomizationLogic, ['uiConfiguration']],
        actions: [
            projectTreeDataLogic,
            ['addShortcutItem', 'loadShortcutsSuccess', 'deleteShortcutSuccess'],
            router,
            ['locationChanged'],
        ],
    })),
    actions({
        showPinHint: true,
        hidePinHint: true,
        checkHasAnalyticsItems: true,
    }),
    loaders(({ values }) => ({
        hasAnalyticsItems: [
            null as boolean | null,
            {
                // Each list request counts every match, so ask one type at a time and stop at the first hit.
                loadHasAnalyticsItems: async (_: void, breakpoint) => {
                    for (const type of values.viewAllTypes) {
                        const page = await api.fileSystem.list({ ...fileSystemTypeParams(type), limit: 1 })
                        breakpoint()
                        if (page.results.length > 0) {
                            return true
                        }
                    }
                    return false
                },
            },
        ],
    })),
    reducers({
        // The hint on the list's first row menu, which shows where to pin an item from.
        pinHintVisible: [
            false,
            {
                showPinHint: () => true,
                hidePinHint: () => false,
                addShortcutItem: () => false,
            },
        ],
    }),
    selectors({
        // The types View all lists, so the placeholder that links there never leads to an empty list.
        viewAllTypes: [
            (s) => [s.uiConfiguration],
            (uiConfiguration: UserUIConfiguration | null): AnalyticsType[] =>
                analyticsFeedTypes({
                    ...EMPTY_ANALYTICS_FEED_QUERY,
                    hideInsights: !!uiConfiguration?.analytics_list?.hide_insights,
                }),
        ],
        pinnedAnalytics: [
            (s) => [s.shortcutData],
            (shortcutData: FileSystemEntry[]): PinnedAnalytics[] =>
                shortcutData.flatMap((shortcut): PinnedAnalytics[] => {
                    if (!shortcut.id || !shortcut.ref) {
                        return []
                    }
                    // A folder shortcut's `path` is its display name; `ref` holds the folder it points at.
                    if (shortcut.type === 'folder') {
                        return isSpacePath(shortcut.ref)
                            ? [
                                  {
                                      kind: 'collection',
                                      key: pinKey('folder', shortcut.ref),
                                      shortcutId: shortcut.id,
                                      path: shortcut.ref,
                                      name: fileSystemEntryName({ path: shortcut.ref }),
                                  },
                              ]
                            : []
                    }
                    const item = fileSystemEntryToAnalytics(shortcut)
                    return item
                        ? [{ kind: 'item', key: pinKey(item.type, item.id), shortcutId: shortcut.id, item }]
                        : []
                }),
        ],
        pinnedCollectionPaths: [
            (s) => [s.pinnedAnalytics],
            (pinnedAnalytics: PinnedAnalytics[]): Set<string> =>
                new Set(pinnedAnalytics.flatMap((pinned) => (pinned.kind === 'collection' ? [pinned.path] : []))),
        ],
    }),
    listeners(({ actions, values }) => ({
        // The answer only matters for the placeholder, which shows with nothing pinned. Once it is yes, it stays yes
        // for the visit.
        checkHasAnalyticsItems: () => {
            if (
                values.hasAnalyticsItems !== true &&
                !values.hasAnalyticsItemsLoading &&
                !values.shortcutDataLoading &&
                values.pinnedAnalytics.length === 0
            ) {
                actions.loadHasAnalyticsItems()
            }
        },
        loadShortcutsSuccess: () => actions.checkHasAnalyticsItems(),
        deleteShortcutSuccess: () => actions.checkHasAnalyticsItems(),
        // Creating a first item navigates to it, and a failed check gets one more try per navigation.
        locationChanged: () => actions.checkHasAnalyticsItems(),
        showPinHint: () => {
            // pinned: analytics event name. Renaming it breaks dashboards.
            posthog.capture('analytics pin hint shown')
        },
    })),
    afterMount(({ actions }) => {
        actions.checkHasAnalyticsItems()
    }),
])
