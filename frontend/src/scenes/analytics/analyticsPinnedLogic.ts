import { MakeLogicType, connect, kea, listeners, path, selectors } from 'kea'
import posthog from 'posthog-js'

import { PinTarget, pinKey, sidebarPinsLogic } from '~/layout/today/sidebar/sidebarPinsLogic'
import { FileSystemEntry } from '~/queries/schema/schema-general'

import {
    AnalyticsItem,
    fileSystemBaseType,
    fileSystemEntryName,
    fileSystemEntryToAnalytics,
    isAnalyticsType,
    isSpacePath,
} from './analyticsUtils'

export type PinnedAnalytics =
    | { kind: 'item'; key: string; shortcutId: string; item: AnalyticsItem }
    | { kind: 'collection'; key: string; shortcutId: string; path: string; name: string }

/** Which analytics pin event a pin change sends, or null for a pin that is not an analytics item or collection. */
function analyticsPinKind(target: PinTarget): 'collection' | 'item' | null {
    const type = fileSystemBaseType(target.type)
    if (type === 'folder') {
        return target.ref && isSpacePath(target.ref) ? 'collection' : null
    }
    return isAnalyticsType(type) ? 'item' : null
}

export function scenePinTarget(entry: FileSystemEntry | null): PinTarget | null {
    const type = fileSystemBaseType(entry?.type)
    if (!entry?.ref || !isAnalyticsType(type)) {
        return null
    }
    return { type, ref: entry.ref, name: fileSystemEntryName(entry), href: entry.href }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsPinnedLogicValues {
    shortcutData: FileSystemEntry[] // sidebarPinsLogic
    pinnedAnalytics: PinnedAnalytics[]
    pinnedCollectionPaths: Set<string>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsPinnedLogicActions {
    pinSettled: (
        target: PinTarget,
        pinned: boolean,
        saved: boolean
    ) => {
        pinned: boolean
        saved: boolean
        target: PinTarget
    } // sidebarPinsLogic
    pinStarted: (
        target: PinTarget,
        pinned: boolean
    ) => {
        pinned: boolean
        target: PinTarget
    } // sidebarPinsLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsPinnedLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        pinnedAnalytics: (shortcutData: FileSystemEntry[]) => PinnedAnalytics[]
        pinnedCollectionPaths: (pinnedAnalytics: PinnedAnalytics[]) => Set<string>
    }
}

export type analyticsPinnedLogicType = MakeLogicType<
    analyticsPinnedLogicValues,
    analyticsPinnedLogicActions,
    Record<string, any>,
    analyticsPinnedLogicMeta
>

/** The analytics items and collections among the sidebar pins, for the Analytics pane's Pinned section. */
export const analyticsPinnedLogic = kea<analyticsPinnedLogicType>([
    path(['scenes', 'analytics', 'analyticsPinnedLogic']),
    connect(() => ({
        values: [sidebarPinsLogic, ['shortcutData']],
        actions: [sidebarPinsLogic, ['pinStarted', 'pinSettled']],
    })),
    selectors({
        pinnedAnalytics: [
            (s) => [s.shortcutData],
            (shortcutData: FileSystemEntry[]): PinnedAnalytics[] =>
                shortcutData.flatMap((shortcut): PinnedAnalytics[] => {
                    if (!shortcut.id || !shortcut.ref) {
                        return []
                    }
                    // A folder shortcut's `path` is its display name; `ref` holds the folder it points at.
                    if (shortcut.type === 'folder') {
                        return isSpacePath(shortcut.ref)
                            ? [
                                  {
                                      kind: 'collection',
                                      key: pinKey('folder', shortcut.ref),
                                      shortcutId: shortcut.id,
                                      path: shortcut.ref,
                                      name: fileSystemEntryName({ path: shortcut.ref }),
                                  },
                              ]
                            : []
                    }
                    const item = fileSystemEntryToAnalytics(shortcut)
                    return item
                        ? [{ kind: 'item', key: pinKey(item.type, item.id), shortcutId: shortcut.id, item }]
                        : []
                }),
        ],
        pinnedCollectionPaths: [
            (s) => [s.pinnedAnalytics],
            (pinnedAnalytics: PinnedAnalytics[]): Set<string> =>
                new Set(pinnedAnalytics.flatMap((pinned) => (pinned.kind === 'collection' ? [pinned.path] : []))),
        ],
    }),
    listeners(({ values, cache }) => ({
        pinStarted: ({ target }) => {
            if (analyticsPinKind(target)) {
                // A pin menu closes on click and can take this logic with it, so it stays mounted until the save
                // settles. Without this, the pin saves but sends no event. Not a disposable: releasing it can unmount
                // this logic, and the unmount would release it a second time.
                cache.releasePinSave?.()
                cache.releasePinSave = analyticsPinnedLogic.mount()
            }
        },
        pinSettled: ({ target, pinned, saved }) => {
            const kind = analyticsPinKind(target)
            if (saved && kind === 'collection') {
                // pinned: analytics event name and `pinned_count`. Renaming them breaks dashboards.
                posthog.capture('analytics collection pinned', {
                    pinned,
                    pinned_count: values.pinnedCollectionPaths.size,
                })
            } else if (saved && kind === 'item') {
                // pinned: analytics event name and properties. Renaming them breaks dashboards.
                posthog.capture('analytics item pinned', { pinned, object_type: fileSystemBaseType(target.type) })
            }
            const release = cache.releasePinSave
            cache.releasePinSave = undefined
            release?.()
        },
    })),
])
