/** The project's spaces: its top-level folders, with what each one holds. */
export const analyticsSpacesLogic = kea<analyticsSpacesLogicType>([
    path(['scenes', 'analytics', 'analyticsSpacesLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
        actions: [todayAnalyticsLogic, ['folderCreated'], projectTreeDataLogic, ['deleteSavedItem']],
    })),
    actions({
        togglePin: (space: Pick<AnalyticsSpace, 'path' | 'name'>) => ({ space }),
        togglePinDone: true,
        setSearch: (search: string) => ({ search }),
        loadMore: true,
        refreshSpaces: true,
        setPagination: (offset: number, hasMore: boolean) => ({ offset, hasMore }),
    }),
    loaders(({ actions, values, cache }) => ({
        shortcuts: [
            [] as FileSystemEntry[],
            {
                loadShortcuts: async () => {
                    cache.shortcutsRequest = api.fileSystemShortcuts.list()
                    return (await cache.shortcutsRequest).results
                },
            },
        ],
        spaces: [
            [] as AnalyticsSpace[],
            {
                loadSpaces: async (append: boolean = false, breakpoint): Promise<AnalyticsSpace[]> => {
                    const controller = new AbortController()
                    cache.disposables.add(() => () => controller.abort(), 'spacesRequest', { pauseOnPageHidden: false })
                    const metadata: Map<string, AnalyticsSpace> = (cache.metadata ??= new Map())
                    let folders: FileSystemEntry[] | undefined = cache.folders
                    if (!folders) {
                        folders = await listSpaceFolders(controller.signal)
                        breakpoint()
                        cache.folders = folders
                    }
                    if (!cache.shortcutsRequest) {
                        actions.loadShortcuts()
                    }
                    const shortcuts: FileSystemEntry[] = (await cache.shortcutsRequest).results
                    breakpoint()
                    const pinned = new Set(shortcuts.filter((item) => item.type === 'folder').map((item) => item.ref))
                    const needle = values.search.trim().toLowerCase()
                    const matches = folders
                        .filter(
                            (folder) =>
                                isSpacePath(folder.path) && fileSystemEntryName(folder).toLowerCase().includes(needle)
                        )
                        .sort((first, second) => {
                            const pinnedFirst = Number(pinned.has(second.path)) - Number(pinned.has(first.path))
                            return pinnedFirst || first.path.localeCompare(second.path)
                        })
                    const offset = append ? values.pagination.offset : 0
                    const page = matches.slice(offset, offset + ANALYTICS_FEED_PAGE_SIZE)
                    const spaces = await Promise.all(
                        page.map(async (folder) => {
                            const existing = metadata.get(folder.path)
                            if (existing) {
                                return existing
                            }
                            const space = await loadSpace(folder, controller.signal)
                            metadata.set(folder.path, space)
                            return space
                        })
                    )
                    breakpoint()
                    cache.loaded = true
                    actions.setPagination(offset + page.length, offset + page.length < matches.length)
                    const combined = append ? [...values.spaces, ...spaces] : spaces
                    return combined.sort((first, second) => first.name.localeCompare(second.name))
                },
            },
        ],
    })),
    reducers({
        pagination: [
            { offset: 0, hasMore: false } as SpacesPagination,
            {
                setPagination: (_, { offset, hasMore }) => ({ offset, hasMore }),
                setSearch: (): SpacesPagination => ({ offset: 0, hasMore: false }),
            },
        ],
        spacesFailed: [
            false,
            { loadSpaces: () => false, loadSpacesSuccess: () => false, loadSpacesFailure: () => true },
        ],
        // The last loaded shortcuts persist, so starred spaces show at once on the next visit and refresh in place.
        shortcuts: [[] as FileSystemEntry[], SHORTCUTS_PERSIST_OPTIONS, {}],
        // The path being pinned or unpinned, so its button shows progress and ignores a second click.
        pinning: [null as string | null, { togglePin: (_, { space }) => space.path, togglePinDone: () => null }],
        search: ['', { setSearch: (_, { search }) => search }],
    }),
    selectors({
        // A starred space is a shortcut to its folder; the shortcut row carries the path.
        pinnedSpaces: [
            (s) => [s.shortcuts],
            (shortcuts: FileSystemEntry[]): PinnedSpace[] =>
                shortcuts.flatMap((shortcut) =>
                    // A shortcut's `path` is its display name; `ref` holds the folder it points at.
                    shortcut.type === 'folder' && shortcut.id && shortcut.ref && isSpacePath(shortcut.ref)
                        ? [
                              {
                                  shortcutId: shortcut.id,
                                  path: shortcut.ref,
                                  name: fileSystemEntryName({ path: shortcut.ref }),
                              },
                          ]
                        : []
                ),
        ],
        pinnedPaths: [
            (s) => [s.pinnedSpaces],
            (pinnedSpaces: PinnedSpace[]): Set<string> => new Set(pinnedSpaces.map((space) => space.path)),
        ],
        // Pinned spaces lead, then the rest alphabetically; a search narrows both by name.
        visibleSpaces: [
            (s) => [s.spaces, s.pinnedPaths, s.search],
            (spaces: AnalyticsSpace[], pinnedPaths: Set<string>, search: string): AnalyticsSpace[] => {
                const needle = search.trim().toLowerCase()
                return spaces
                    .filter((space) => !needle || space.name.toLowerCase().includes(needle))
                    .sort((first, second) => {
                        const pinnedFirst = Number(pinnedPaths.has(second.path)) - Number(pinnedPaths.has(first.path))
                        return pinnedFirst || first.name.localeCompare(second.name)
                    })
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        refreshSpaces: () => {
            cache.folders = undefined
            cache.metadata = new Map<string, AnalyticsSpace>()
            actions.loadSpaces()
        },
        loadShortcutsFailure: () => {
            cache.shortcutsRequest = undefined
        },
        loadShortcutsSuccess: () => {
            if (cache.loaded && removeProjectIdIfPresent(router.values.location.pathname) === urls.analyticsSpaces()) {
                actions.loadSpaces()
            }
        },
        loadMore: () => {
            if (!values.spacesLoading && values.pagination.hasMore) {
                actions.loadSpaces(true)
            }
        },
        setSearch: async (_, breakpoint) => {
            await breakpoint(200)
            actions.loadSpaces()
        },
        togglePin: async ({ space }) => {
            try {
                const pinned = values.pinnedSpaces.find((candidate) => candidate.path === space.path)
                if (pinned) {
                    await api.fileSystemShortcuts.delete(pinned.shortcutId)
                    toast.success({ title: `Unpinned ${space.name}` })
                } else {
                    // A folder shortcut keeps its path as ref, so a rename moves the star with the folder.
                    await api.fileSystemShortcuts.create({ path: space.path, type: 'folder', ref: space.path })
                    toast.success({ title: `Pinned ${space.name} to the sidebar` })
                }
                actions.loadShortcuts()
            } catch {
                toast.error({ title: 'Couldn’t update the pin. Try again.' })
            }
            actions.togglePinDone()
        },
    })),
    listeners(({ actions, values, cache }) => ({
        // Flags can arrive after the mount, so a mount that skipped the load must load now.
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
            if (!values.featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV] || cache.flagSeen) {
                return
            }
            cache.flagSeen = true
            actions.loadShortcuts()
            if (removeProjectIdIfPresent(router.values.location.pathname) === urls.analyticsSpaces()) {
                actions.refreshSpaces()
            }
        },
        // A space made from the dialog shows up without a reload.
        folderCreated: () => {
            if (removeProjectIdIfPresent(router.values.location.pathname) === urls.analyticsSpaces()) {
                actions.refreshSpaces()
            }
        },
        // A collection is deleted like any folder, through the project tree. The server keeps its pin, so it goes here.
        deleteSavedItem: async ({ savedItem }) => {
            if (savedItem.type !== 'folder' || !isSpacePath(savedItem.path)) {
                return
            }
            const pin = values.pinnedSpaces.find((candidate) => candidate.path === savedItem.path)
            if (pin) {
                await api.fileSystemShortcuts.delete(pin.shortcutId).catch(() => null)
            }
            // pinned: analytics event name. Renaming it breaks dashboards.
            posthog.capture('analytics collection deleted')
            actions.loadShortcuts()
            if (removeProjectIdIfPresent(router.values.location.pathname) === urls.analyticsSpaces()) {
                actions.refreshSpaces()
            }
        },
        togglePinDone: () => {
            // pinned: analytics event name and property. Renaming them breaks dashboards.
            posthog.capture('analytics collection pinned', { pinned_count: values.pinnedSpaces.length })
        },
    })),
    // The sidebar mounts this logic for the stars alone; counting every space is for the Spaces page.
    urlToAction(({ actions, values }) => ({
        [urls.analyticsSpaces()]: () => {
            if (values.featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV]) {
                actions.refreshSpaces()
            }
        },
    })),
    afterMount(({ actions, values, cache }) => {
        if (values.featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV]) {
            cache.flagSeen = true
            actions.loadShortcuts()
        }
    }),
])
