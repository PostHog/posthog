// A canvas stays visible to its channel's members alone, whatever folder holds it, so a space can only
// share one that sits in a public channel.
async function assertCanvasShareable(ref: string): Promise<void> {
    const projectId = String(teamLogic.values.currentTeamId)
    const canvas = await canvasesRetrieve(projectId, ref)
    const channel = await taskChannelsRetrieve(projectId, canvas.channel)
    if (channel.channel_type !== 'public') {
        throw new Error(
            'This canvas is in a private channel, so only its members can open it. Move it to a public channel first.'
        )
    }
}

function folderOfEntry(entry: FileSystemEntry | null): string | null {
    if (!entry || analyticsSpaceOfPath(entry.path) === null) {
        return null
    }
    return joinPath(splitPath(entry.path).slice(0, -1))
}

function toDestination(entry: FileSystemEntry): ShareDestination {
    return { path: entry.path, name: fileSystemEntryName(entry) }
}

async function listChildFolders(parent: string, depth: number, breakpoint: () => void): Promise<FileSystemEntry[]> {
    const folders: FileSystemEntry[] = []
    for (let offset = 0; ; offset += 200) {
        const page = await api.fileSystem.list({ parent, depth, type: 'folder', limit: 200, offset })
        // Stops the scan of a folder the user has already left.
        breakpoint()
        folders.push(...page.results)
        if (!page.next || !page.results.length) {
            return folders
        }
    }
}

async function findEntry(target: ShareToSpaceTarget): Promise<FileSystemEntry | null> {
    const found = await api.fileSystem.list({ ref: target.ref, ...fileSystemTypeParams(target.type) })
    return found.results[0] ?? null
}

/** Moves an item into a space, or back to personal, so the people in that space find it from the Analytics pane. */
export const analyticsShareLogic = kea<analyticsShareLogicType>([
    path(['scenes', 'analytics', 'analyticsShareLogic']),
    connect(() => ({
        actions: [
            analyticsSpacesLogic,
            ['refreshSpaces'],
            projectTreeDataLogic,
            ['createSavedItem'],
            todayAnalyticsLogic,
            ['folderCreated'],
        ],
    })),
    actions({
        openShareToSpace: (target: ShareToSpaceTarget) => ({ target }),
        closeShareToSpace: true,
        entryLoaded: (entry: FileSystemEntry | null) => ({ entry }),
        shareToSpaceDone: true,
        loadItemSpace: (target: ShareToSpaceTarget) => ({ target }),
        /** Moves an item straight into a collection or folder, or to personal with null, with no dialog. */
        moveItem: (target: ShareToSpaceTarget, destination: ShareDestination | null) => ({ target, destination }),
        itemSpaceLoaded: (key: string, space: string | null) => ({ key, space }),
        /** Opens a collection or folder in the dialog. Null shows every collection. */
        browseTo: (path: string | null) => ({ path }),
        setPickerSearch: (search: string) => ({ search }),
        setNewFolderOpen: (open: boolean) => ({ open }),
        setNewFolderName: (name: string) => ({ name }),
        createFolder: true,
        folderCreationFinished: true,
        moveHere: true,
    }),
    loaders(({ values }) => ({
        spaces: [
            [] as AnalyticsSpace[],
            {
                loadSpaces: async (_: void, breakpoint): Promise<AnalyticsSpace[]> => {
                    const folders = await listSpaceFolders()
                    breakpoint()
                    const spaces = await Promise.all(folders.map((folder) => loadSpace(folder)))
                    breakpoint()
                    return spaces.sort((first, second) => first.name.localeCompare(second.name))
                },
            },
        ],
        folderContents: [
            [] as FolderContentsEntry[],
            {
                loadFolderContents: async (_: void, breakpoint): Promise<FolderContentsEntry[]> => {
                    const parent = values.browsePath
                    if (parent === null) {
                        return []
                    }
                    const depth = splitPath(parent).length + 1
                    // Folders load apart from items, so a full page of items cannot hide a folder to move into.
                    const [folders, items] = await Promise.all([
                        listChildFolders(parent, depth, breakpoint),
                        api.fileSystem.list({ parent, depth, notType: 'folder', limit: 100 }),
                    ])
                    breakpoint()
                    const byName = (first: FolderContentsEntry, second: FolderContentsEntry): number =>
                        first.name.localeCompare(second.name)
                    const itemRows: FolderContentsEntry[] = []
                    for (const entry of items.results) {
                        const baseType = fileSystemBaseType(entry.type)
                        if (isAnalyticsType(baseType)) {
                            itemRows.push({ ...toDestination(entry), kind: baseType })
                        }
                    }
                    return [
                        ...folders.map((entry) => ({ ...toDestination(entry), kind: 'folder' as const })).sort(byName),
                        ...itemRows.sort(byName),
                    ]
                },
            },
        ],
        searchResults: [
            [] as ShareDestination[],
            {
                loadSearchResults: async (_: void, breakpoint): Promise<ShareDestination[]> => {
                    const search = values.pickerSearch.trim()
                    if (!search) {
                        return []
                    }
                    await breakpoint(250)
                    const response = await api.fileSystem.list({
                        type: 'folder',
                        search,
                        searchNameOnly: true,
                        limit: 50,
                    })
                    breakpoint()
                    // Unfiled and home folders are personal, so they are not places to move an item to.
                    return response.results
                        .filter((entry) => analyticsSpaceOfPath(entry.path) !== null)
                        .map(toDestination)
                        .sort((first, second) => first.path.localeCompare(second.path))
                },
            },
        ],
    })),
    reducers({
        target: [
            null as ShareToSpaceTarget | null,
            {
                openShareToSpace: (_, { target }) => target,
                closeShareToSpace: () => null,
                shareToSpaceDone: () => null,
            },
        ],
        entry: [
            null as FileSystemEntry | null,
            {
                openShareToSpace: () => null,
                entryLoaded: (_, { entry }) => entry,
                closeShareToSpace: () => null,
            },
        ],
        entryLoading: [
            false,
            { openShareToSpace: () => true, entryLoaded: () => false, closeShareToSpace: () => false },
        ],
        sharing: [false, { moveItem: () => true, shareToSpaceDone: () => false, closeShareToSpace: () => false }],
        browsePath: [
            null as string | null,
            {
                openShareToSpace: () => null,
                browseTo: (_, { path }) => path,
            },
        ],
        pickerSearch: [
            '',
            {
                openShareToSpace: () => '',
                browseTo: () => '',
                setPickerSearch: (_, { search }) => search,
            },
        ],
        folderContentsFailed: [false, { loadFolderContents: () => false, loadFolderContentsFailure: () => true }],
        searchResultsFailed: [false, { loadSearchResults: () => false, loadSearchResultsFailure: () => true }],
        newFolderOpen: [
            false,
            {
                setNewFolderOpen: (_, { open }) => open,
                openShareToSpace: () => false,
                browseTo: () => false,
                setPickerSearch: () => false,
            },
        ],
        creatingFolder: [false, { createFolder: () => true, folderCreationFinished: () => false }],
        newFolderName: [
            '',
            {
                setNewFolderName: (_, { name }) => name,
                setNewFolderOpen: () => '',
                openShareToSpace: () => '',
                browseTo: () => '',
                setPickerSearch: () => '',
            },
        ],
        // The space each looked-up item sits in, so a page can label its action "Move" or "Share" before the dialog opens.
        itemSpaces: [
            {} as Record<string, string | null>,
            {
                itemSpaceLoaded: (state, { key, space }) => ({ ...state, [key]: space }),
            },
        ],
    }),
    selectors({
        pickerSearching: [(s) => [s.pickerSearch], (pickerSearch: string): boolean => pickerSearch.trim() !== ''],
        pickerRows: [
            (s) => [s.pickerSearching, s.browsePath, s.searchResults, s.spaces, s.folderContents],
            (
                searching: boolean,
                browsePath: string | null,
                searchResults: ShareDestination[],
                spaces: AnalyticsSpace[],
                folderContents: FolderContentsEntry[]
            ): PickerRow[] => {
                if (searching) {
                    return searchResults.map((result) => ({
                        ...result,
                        kind: 'folder',
                        description: splitPath(result.path).slice(0, -1).join(' / ') || undefined,
                    }))
                }
                if (browsePath !== null) {
                    return folderContents
                }
                return spaces.map((space) => ({
                    path: space.path,
                    name: space.name,
                    kind: 'folder',
                    description: space.total === 0 ? 'Empty' : `${space.total} ${space.total === 1 ? 'item' : 'items'}`,
                }))
            },
        ],
        pickerLoading: [
            (s) => [
                s.entryLoading,
                s.pickerSearching,
                s.browsePath,
                s.searchResultsLoading,
                s.spacesLoading,
                s.spaces,
                s.folderContentsLoading,
            ],
            (
                entryLoading: boolean,
                searching: boolean,
                browsePath: string | null,
                searchResultsLoading: boolean,
                spacesLoading: boolean,
                spaces: AnalyticsSpace[],
                folderContentsLoading: boolean
            ): boolean => {
                if (entryLoading) {
                    return true
                }
                if (searching) {
                    return searchResultsLoading
                }
                return browsePath === null ? spacesLoading && !spaces.length : folderContentsLoading
            },
        ],
        pickerErrorMessage: [
            (s) => [s.pickerSearching, s.browsePath, s.searchResultsFailed, s.folderContentsFailed],
            (
                searching: boolean,
                browsePath: string | null,
                searchResultsFailed: boolean,
                folderContentsFailed: boolean
            ): string | null => {
                if (searching) {
                    return searchResultsFailed
                        ? 'Couldn’t search collections and folders. Change the search to try again.'
                        : null
                }
                return browsePath !== null && folderContentsFailed
                    ? 'Couldn’t load this folder. Close this and try again.'
                    : null
            },
        ],
        pickerEmptyMessage: [
            (s) => [s.pickerSearching, s.pickerSearch, s.browsePath],
            (searching: boolean, pickerSearch: string, browsePath: string | null): string => {
                if (searching) {
                    return `No collections or folders match "${pickerSearch.trim()}"`
                }
                if (browsePath === null) {
                    return 'No collections yet'
                }
                return splitPath(browsePath).length === 1
                    ? 'No items in this collection yet'
                    : 'No items in this folder yet'
            },
        ],
        currentFolder: [(s) => [s.entry], (entry: FileSystemEntry | null): string | null => folderOfEntry(entry)],
        moveButtonLabel: [
            (s) => [s.currentFolder, s.browseCrumbs, s.pickerSearching],
            (currentFolder: string | null, browseCrumbs: ShareDestination[], searching: boolean): string => {
                const verb = currentFolder !== null ? 'Move' : 'Add'
                const destination = browseCrumbs.at(-1)
                return destination && !searching ? `${verb} to ${destination.name}` : verb
            },
        ],
        browseCrumbs: [
            (s) => [s.browsePath],
            (browsePath: string | null): ShareDestination[] => {
                const segments = browsePath === null ? [] : splitPath(browsePath)
                return segments.map((segment, index) => ({
                    name: segment,
                    path: joinPath(segments.slice(0, index + 1)),
                }))
            },
        ],
        moveDisabledReason: [
            (s) => [s.browsePath, s.currentFolder, s.entryLoading, s.sharing, s.pickerSearch],
            (
                browsePath: string | null,
                currentFolder: string | null,
                entryLoading: boolean,
                sharing: boolean,
                pickerSearch: string
            ): string | null => {
                // The open folder sits behind the search results, so moving there would surprise the user.
                if (pickerSearch.trim()) {
                    return 'Open a result first'
                }
                if (browsePath === null) {
                    return 'Open a collection or folder first'
                }
                if (browsePath === currentFolder) {
                    return 'It’s already here'
                }
                if (entryLoading || sharing) {
                    return 'Working…'
                }
                return null
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        openShareToSpace: async ({ target }, breakpoint) => {
            // The collections and their counts change behind this dialog, so each open reads them again.
            actions.loadSpaces()
            try {
                const entry = await findEntry(target)
                breakpoint()
                actions.entryLoaded(entry)
                actions.itemSpaceLoaded(shareTargetKey(target), entry ? analyticsSpaceOfPath(entry.path) : null)
            } catch (error) {
                if ((error as { isBreakpoint?: boolean }).isBreakpoint) {
                    throw error
                }
                actions.entryLoaded(null)
            }
        },
        loadItemSpace: async ({ target }) => {
            // A failed lookup records nothing, so the item is not mistaken for one in no collection.
            const entry = await findEntry(target).catch(() => undefined)
            if (entry !== undefined) {
                actions.itemSpaceLoaded(shareTargetKey(target), entry ? analyticsSpaceOfPath(entry.path) : null)
            }
        },
        browseTo: () => {
            actions.loadFolderContents()
        },
        setPickerSearch: () => {
            actions.loadSearchResults()
        },
        moveHere: () => {
            const destination = values.browseCrumbs.at(-1)
            if (values.target && destination && !values.moveDisabledReason) {
                actions.moveItem(values.target, destination)
            }
        },
        createFolder: async () => {
            const parent = values.browsePath
            const name = values.newFolderName.trim()
            // One name is one segment: a slash in it must not create a nested folder.
            const path = parent ? `${parent}/${escapePath(name)}` : escapePath(name)
            if (parent === null && !isSpacePath(path)) {
                toast.error({ title: `"${name}" is a reserved name. Pick another name for the collection.` })
                actions.folderCreationFinished()
                return
            }
            try {
                const entry = await api.fileSystem.create({ path, type: 'folder' } as FileSystemEntry)
                // The project tree keeps the rows, so the new folder shows wherever the tree is open.
                actions.createSavedItem(entry)
                // Pages that list collections and folders reload on this.
                actions.folderCreated()
                // pinned: analytics event name. Renaming it breaks dashboards.
                posthog.capture('analytics folder created', { nested: parent !== null, source: 'move dialog' })
                if (parent === null) {
                    actions.loadSpaces()
                }
                // The user may have closed the dialog or opened another folder while the folder was created.
                if (values.target && values.browsePath === parent) {
                    actions.browseTo(entry.path)
                }
            } catch {
                toast.error({
                    title: parent
                        ? 'Couldn’t create the folder. Try again.'
                        : 'Couldn’t create the collection. Try again.',
                })
            }
            actions.folderCreationFinished()
        },
        moveItem: async ({ target, destination }) => {
            try {
                const dialogEntry =
                    values.target && shareTargetKey(values.target) === shareTargetKey(target) ? values.entry : null
                const entry = dialogEntry ?? (await findEntry(target))
                if (!entry) {
                    throw new Error('This item has no row in the project file system yet.')
                }
                if (target.type === 'canvas' && destination) {
                    await assertCanvasShareable(target.ref)
                }
                const wasShared = analyticsSpaceOfPath(entry.path) !== null
                const folder = destination
                    ? destination.path
                    : `${UNFILED_FOLDER}/${ANALYTICS_TYPE_INFO[target.type].pluralLabel}`
                await api.fileSystem.move(entry.id, `${folder}/${escapePath(target.name)}`)
                toast.success({
                    title: destination
                        ? wasShared
                            ? `Moved to ${destination.name}`
                            : `Added to ${destination.name}`
                        : 'Removed from its collection',
                })
                actions.itemSpaceLoaded(
                    shareTargetKey(target),
                    destination ? analyticsSpaceOfPath(destination.path) : null
                )
                if (removeProjectIdIfPresent(router.values.location.pathname) === urls.analyticsSpaces()) {
                    actions.refreshSpaces()
                }
                // pinned: analytics event name and properties. Renaming them breaks dashboards.
                posthog.capture('analytics item moved', {
                    type: target.type,
                    from: wasShared ? 'space' : 'personal',
                    to: destination ? 'space' : 'personal',
                    into_folder: destination ? splitPath(destination.path).length > 1 : false,
                })
            } catch (error) {
                toast.error({ title: error instanceof Error ? error.message : 'Couldn’t move this item.' })
            }
            actions.shareToSpaceDone()
        },
    })),
])
