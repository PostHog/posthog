async function findEntry(target: ShareToSpaceTarget): Promise<FileSystemEntry | null> {
    const found = await api.fileSystem.list({ ref: target.ref, ...fileSystemTypeParams(target.type) })
    return found.results[0] ?? null
}

/** Moves an item into a space, or back to personal, so the people in that space find it from the Analytics pane. */
export const analyticsShareLogic = kea<analyticsShareLogicType>([
    path(['scenes', 'analytics', 'analyticsShareLogic']),
    connect(() => ({
        values: [analyticsSpacesLogic, ['spaces', 'spacesLoading']],
        actions: [analyticsSpacesLogic, ['loadSpaces']],
    })),
    actions({
        openShareToSpace: (target: ShareToSpaceTarget) => ({ target }),
        closeShareToSpace: true,
        entryLoaded: (entry: FileSystemEntry | null) => ({ entry }),
        /** Null moves the item out of every space, back to personal. */
        shareToSpace: (space: AnalyticsSpace | null) => ({ space }),
        shareToSpaceDone: true,
        loadItemSpace: (target: ShareToSpaceTarget) => ({ target }),
        /** Moves an item straight into a space, or to personal with null, with no dialog. */
        moveItem: (target: ShareToSpaceTarget, space: AnalyticsSpace | null) => ({ target, space }),
        itemSpaceLoaded: (key: string, space: string | null) => ({ key, space }),
    }),
    reducers({
        target: [
            null as ShareToSpaceTarget | null,
            {
                openShareToSpace: (_, { target }) => target,
                closeShareToSpace: () => null,
                shareToSpaceDone: () => null,
            },
        ],
        entry: [
            null as FileSystemEntry | null,
            {
                openShareToSpace: () => null,
                entryLoaded: (_, { entry }) => entry,
                closeShareToSpace: () => null,
            },
        ],
        entryLoading: [
            false,
            { openShareToSpace: () => true, entryLoaded: () => false, closeShareToSpace: () => false },
        ],
        sharing: [false, { moveItem: () => true, shareToSpaceDone: () => false, closeShareToSpace: () => false }],
        // The space each looked-up item sits in, so a page can label its action "Move" or "Share" before the dialog opens.
        itemSpaces: [
            {} as Record<string, string | null>,
            {
                itemSpaceLoaded: (state, { key, space }) => ({ ...state, [key]: space }),
            },
        ],
    }),
    selectors({
        currentSpace: [
            (s) => [s.entry],
            (entry: FileSystemEntry | null): string | null => (entry ? analyticsSpaceOfPath(entry.path) : null),
        ],
    }),
    listeners(({ actions, values }) => ({
        openShareToSpace: async ({ target }, breakpoint) => {
            if (!values.spaces.length && !values.spacesLoading) {
                actions.loadSpaces()
            }
            const entry = await findEntry(target).catch(() => null)
            breakpoint()
            actions.entryLoaded(entry)
            actions.itemSpaceLoaded(shareTargetKey(target), entry ? analyticsSpaceOfPath(entry.path) : null)
        },
        loadItemSpace: async ({ target }) => {
            const entry = await findEntry(target).catch(() => null)
            actions.itemSpaceLoaded(shareTargetKey(target), entry ? analyticsSpaceOfPath(entry.path) : null)
        },
        shareToSpace: ({ space }) => {
            if (values.target) {
                actions.moveItem(values.target, space)
            }
        },
        moveItem: async ({ target, space }) => {
            try {
                const entry = values.target && values.entry ? values.entry : await findEntry(target)
                if (!entry) {
                    throw new Error('This item has no row in the project file system yet.')
                }
                const wasShared = analyticsSpaceOfPath(entry.path) !== null
                const folder = space ? space.path : `${UNFILED_FOLDER}/${ANALYTICS_TYPE_INFO[target.type].pluralLabel}`
                await api.fileSystem.move(entry.id, `${folder}/${escapePath(target.name)}`)
                lemonToast.success(
                    space ? (wasShared ? `Moved to ${space.name}` : `Shared into ${space.name}`) : 'Made personal'
                )
                actions.itemSpaceLoaded(shareTargetKey(target), space ? space.name : null)
                actions.loadSpaces()
            } catch (error) {
                lemonToast.error(error instanceof Error ? error.message : 'Could not move this item.')
            }
            actions.shareToSpaceDone()
        },
    })),
])
