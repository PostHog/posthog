// A canvas stays visible to its channel's members alone, whatever folder holds it, so a space can only
// share one that sits in a public channel.
async function assertCanvasShareable(ref: string): Promise<void> {
    const projectId = String(teamLogic.values.currentTeamId)
    const canvas = await canvasesRetrieve(projectId, ref)
    const channel = await taskChannelsRetrieve(projectId, canvas.channel)
    if (channel.channel_type !== 'public') {
        throw new Error(
            'This canvas is in a private channel, so only its members can open it. Move it to a public channel first.'
        )
    }
}

async function findEntry(target: ShareToSpaceTarget): Promise<FileSystemEntry | null> {
    const found = await api.fileSystem.list({ ref: target.ref, ...fileSystemTypeParams(target.type) })
    return found.results[0] ?? null
}

/** Moves one item into a space, or back to personal with null, and says whether it sat in a space before. */
async function moveToSpace(
    target: ShareToSpaceTarget,
    space: AnalyticsSpace | null,
    knownEntry: FileSystemEntry | null
): Promise<{ wasShared: boolean }> {
    const entry = knownEntry ?? (await findEntry(target))
    if (!entry) {
        throw new Error('This item has no row in the project file system yet.')
    }
    if (target.type === 'canvas' && space) {
        await assertCanvasShareable(target.ref)
    }
    const wasShared = analyticsSpaceOfPath(entry.path) !== null
    const folder = space ? space.path : `${UNFILED_FOLDER}/${ANALYTICS_TYPE_INFO[target.type].pluralLabel}`
    await api.fileSystem.move(entry.id, `${folder}/${escapePath(target.name)}`)
    return { wasShared }
}

/** Moves an item into a space, or back to personal, so the people in that space find it from the Analytics pane. */
export const analyticsShareLogic = kea<analyticsShareLogicType>([
    path(['scenes', 'analytics', 'analyticsShareLogic']),
    connect(() => ({
        actions: [analyticsSpacesLogic, ['refreshSpaces']],
    })),
    actions({
        openShareToSpace: (target: ShareToSpaceTarget) => ({ target }),
        /** Opens the dialog for several items at once, which all go to the space the person picks. */
        openBulkShareToSpace: (targets: ShareToSpaceTarget[]) => ({ targets }),
        closeShareToSpace: true,
        entryLoaded: (entry: FileSystemEntry | null) => ({ entry }),
        /** Null moves the item out of every space, back to personal. */
        shareToSpace: (space: AnalyticsSpace | null) => ({ space }),
        shareToSpaceDone: true,
        loadItemSpace: (target: ShareToSpaceTarget) => ({ target }),
        /** Moves an item straight into a space, or to personal with null, with no dialog. */
        moveItem: (target: ShareToSpaceTarget, space: AnalyticsSpace | null) => ({ target, space }),
        moveItems: (targets: ShareToSpaceTarget[], space: AnalyticsSpace) => ({ targets, space }),
        /** The items a bulk move placed, so a selection of them can clear. */
        itemsMoved: (moved: ShareToSpaceTarget[]) => ({ moved }),
        itemSpaceLoaded: (key: string, space: string | null) => ({ key, space }),
    }),
    loaders({
        spaces: [
            [] as AnalyticsSpace[],
            {
                loadSpaces: async (_: void, breakpoint): Promise<AnalyticsSpace[]> => {
                    const folders = await listSpaceFolders()
                    breakpoint()
                    const spaces = await Promise.all(folders.map((folder) => loadSpace(folder)))
                    breakpoint()
                    return spaces.sort((first, second) => first.name.localeCompare(second.name))
                },
            },
        ],
    }),
    reducers({
        target: [
            null as ShareToSpaceTarget | null,
            {
                openShareToSpace: (_, { target }) => target,
                openBulkShareToSpace: () => null,
                closeShareToSpace: () => null,
                shareToSpaceDone: () => null,
            },
        ],
        bulkTargets: [
            [] as ShareToSpaceTarget[],
            {
                openBulkShareToSpace: (_, { targets }) => targets,
                openShareToSpace: () => [],
                closeShareToSpace: () => [],
                shareToSpaceDone: () => [],
            },
        ],
        entry: [
            null as FileSystemEntry | null,
            {
                openShareToSpace: () => null,
                openBulkShareToSpace: () => null,
                entryLoaded: (_, { entry }) => entry,
                closeShareToSpace: () => null,
            },
        ],
        entryLoading: [
            false,
            {
                openShareToSpace: () => true,
                openBulkShareToSpace: () => false,
                entryLoaded: () => false,
                closeShareToSpace: () => false,
            },
        ],
        sharing: [
            false,
            {
                moveItem: () => true,
                moveItems: () => true,
                shareToSpaceDone: () => false,
                closeShareToSpace: () => false,
            },
        ],
        // The space each looked-up item sits in, so a page can label its action "Move" or "Share" before the dialog opens.
        itemSpaces: [
            {} as Record<string, string | null>,
            {
                itemSpaceLoaded: (state, { key, space }) => ({ ...state, [key]: space }),
            },
        ],
    }),
    selectors({
        currentSpace: [
            (s) => [s.entry],
            (entry: FileSystemEntry | null): string | null => (entry ? analyticsSpaceOfPath(entry.path) : null),
        ],
    }),
    listeners(({ actions, values }) => ({
        openShareToSpace: async ({ target }, breakpoint) => {
            // The collections and their counts change behind this dialog, so each open reads them again.
            actions.loadSpaces()
            const entry = await findEntry(target).catch(() => null)
            breakpoint()
            actions.entryLoaded(entry)
            actions.itemSpaceLoaded(shareTargetKey(target), entry ? analyticsSpaceOfPath(entry.path) : null)
        },
        openBulkShareToSpace: () => {
            actions.loadSpaces()
        },
        loadItemSpace: async ({ target }) => {
            const entry = await findEntry(target).catch(() => null)
            actions.itemSpaceLoaded(shareTargetKey(target), entry ? analyticsSpaceOfPath(entry.path) : null)
        },
        shareToSpace: ({ space }) => {
            if (values.bulkTargets.length) {
                if (space) {
                    actions.moveItems(values.bulkTargets, space)
                }
            } else if (values.target) {
                actions.moveItem(values.target, space)
            }
        },
        moveItem: async ({ target, space }) => {
            try {
                const { wasShared } = await moveToSpace(
                    target,
                    space,
                    values.target && values.entry ? values.entry : null
                )
                toast.success({
                    title: space
                        ? wasShared
                            ? `Moved to ${space.name}`
                            : `Added to ${space.name}`
                        : 'Removed from its collection',
                })
                actions.itemSpaceLoaded(shareTargetKey(target), space ? space.name : null)
                if (removeProjectIdIfPresent(router.values.location.pathname) === urls.analyticsSpaces()) {
                    actions.refreshSpaces()
                }
                // pinned: analytics event name and properties. Renaming them breaks dashboards.
                posthog.capture('analytics item moved', {
                    type: target.type,
                    from: wasShared ? 'space' : 'personal',
                    to: space ? 'space' : 'personal',
                })
            } catch (error) {
                toast.error({ title: error instanceof Error ? error.message : 'Couldn’t move this item.' })
            }
            actions.shareToSpaceDone()
        },
        moveItems: async ({ targets, space }) => {
            const moved: ShareToSpaceTarget[] = []
            let firstError: string | null = null
            for (const target of targets) {
                try {
                    await moveToSpace(target, space, null)
                    moved.push(target)
                    actions.itemSpaceLoaded(shareTargetKey(target), space.name)
                } catch (error) {
                    firstError ??= error instanceof Error ? error.message : 'Couldn’t move this item.'
                }
            }
            const failed = targets.length - moved.length
            if (!failed) {
                toast.success({ title: `Added ${pluralize(moved.length, 'item')} to ${space.name}` })
            } else if (moved.length) {
                toast.warning({
                    title: `Added ${moved.length} of ${pluralize(targets.length, 'item')} to ${space.name}`,
                    description: firstError ?? undefined,
                })
            } else {
                toast.error({
                    title: `Couldn’t add ${pluralize(targets.length, 'item')} to ${space.name}`,
                    description: firstError ?? undefined,
                })
            }
            if (moved.length) {
                actions.itemsMoved(moved)
                if (removeProjectIdIfPresent(router.values.location.pathname) === urls.analyticsSpaces()) {
                    actions.refreshSpaces()
                }
            }
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics items moved', {
                item_count: targets.length,
                moved_count: moved.length,
                types: [...new Set(targets.map((target) => target.type))],
            })
            actions.shareToSpaceDone()
        },
    })),
])
