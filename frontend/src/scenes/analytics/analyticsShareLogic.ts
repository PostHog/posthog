import { fileSystemTypeParams } from './analyticsFeed'
import { AnalyticsSpace, analyticsSpacesLogic } from './analyticsSpacesLogic'
import { ANALYTICS_TYPE_INFO, AnalyticsType, UNFILED_FOLDER, analyticsSpaceOfPath } from './analyticsUtils'

export interface ShareToSpaceTarget {
    type: AnalyticsType
    ref: string
    name: string
}

export function shareTargetKey(target: Pick<ShareToSpaceTarget, 'type' | 'ref'>): string {
    return `${target.type}:${target.ref}`
}

