import { MakeLogicType, actions, kea, listeners, path, reducers } from 'kea'
import posthog from 'posthog-js'

import { toast } from '@posthog/quill'

import api from 'lib/api'
import { insightsApi } from 'scenes/insights/utils/api'
import { teamLogic } from 'scenes/teamLogic'

import { InsightShortId } from '~/types'

import { dashboardsCreate } from 'products/dashboards/frontend/generated/api'

import type { TaggableAnalyticsType } from './analyticsFeed'
import { AnalyticsItem } from './analyticsUtils'

type DuplicableItem = AnalyticsItem & { type: TaggableAnalyticsType }

export function analyticsItemKey(item: Pick<AnalyticsItem, 'type' | 'id'>): string {
    return `${item.type}:${item.id}`
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsItemActionsLogicValues {
    deleteTarget: AnalyticsItem | null
    deleting: boolean
    duplicating: Record<string, true>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsItemActionsLogicActions {
    closeDeleteConfirm: () => {
        value: true
    }
    deleteItem: () => {
        value: true
    }
    deleteItemFailure: () => {
        value: true
    }
    duplicateFinished: (key: string) => {
        key: string
    }
    duplicateItem: (item: DuplicableItem) => {
        item: DuplicableItem
    }
    duplicateStarted: (key: string) => {
        key: string
    }
    itemChanged: () => {
        value: true
    }
    openDeleteConfirm: (item: AnalyticsItem) => {
        item: AnalyticsItem
    }
}

export type analyticsItemActionsLogicType = MakeLogicType<
    analyticsItemActionsLogicValues,
    analyticsItemActionsLogicActions
>

/** The Analytics list's row actions that change the item itself: duplicating it, and deleting it once confirmed. */
export const analyticsItemActionsLogic = kea<analyticsItemActionsLogicType>([
    path(['scenes', 'analytics', 'analyticsItemActionsLogic']),
    actions({
        duplicateItem: (item: DuplicableItem) => ({ item }),
        duplicateStarted: (key: string) => ({ key }),
        duplicateFinished: (key: string) => ({ key }),
        openDeleteConfirm: (item: AnalyticsItem) => ({ item }),
        closeDeleteConfirm: true,
        deleteItem: true,
        deleteItemFailure: true,
        /** The list reads again after this, so the copy shows up and the deleted row goes. */
        itemChanged: true,
    }),
    reducers({
        // The items with a copy in flight, so the menu cannot start a second copy of the same one.
        duplicating: [
            {} as Record<string, true>,
            {
                duplicateStarted: (state, { key }) => ({ ...state, [key]: true }),
                duplicateFinished: (state, { key }) => {
                    const { [key]: _, ...rest } = state
                    return rest
                },
            },
        ],
        deleteTarget: [
            null as AnalyticsItem | null,
            {
                openDeleteConfirm: (_, { item }) => item,
                closeDeleteConfirm: () => null,
                itemChanged: () => null,
            },
        ],
        deleting: [false, { deleteItem: () => true, deleteItemFailure: () => false, itemChanged: () => false }],
    }),
    listeners(({ actions, values }) => ({
        duplicateItem: async ({ item }) => {
            const key = analyticsItemKey(item)
            if (values.duplicating[key]) {
                return
            }
            actions.duplicateStarted(key)
            try {
                if (item.type === 'dashboard') {
                    await dashboardsCreate(String(teamLogic.values.currentTeamId), {
                        use_dashboard: Number(item.id),
                        name: `${item.name} (Copy)`,
                    })
                } else {
                    // The basic read leaves out the cached results, which the copy does not keep anyway.
                    const insight = await insightsApi.getByShortId(item.id as InsightShortId, true)
                    if (!insight) {
                        throw new Error('missing insight')
                    }
                    await insightsApi.duplicate(insight)
                }
            } catch {
                actions.duplicateFinished(key)
                toast.error({ title: `Couldn't duplicate "${item.name}". Try again.` })
                return
            }
            actions.duplicateFinished(key)
            toast.success({ title: `Duplicated "${item.name}"` })
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics item duplicated', { type: item.type })
            actions.itemChanged()
        },
        deleteItem: async () => {
            const item = values.deleteTarget
            if (!item?.entry?.id) {
                return
            }
            let deleted
            try {
                deleted = (await api.fileSystem.delete(item.entry.id))?.deleted ?? []
            } catch {
                actions.deleteItemFailure()
                toast.error({ title: `Couldn't delete "${item.name}". Try again.` })
                return
            }
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics item deleted', { type: item.type, removed_entry_only: !deleted.length })
            // The file system keeps an item that another folder still links to and removes only this entry.
            if (!deleted.length) {
                toast.success({
                    title: `Removed "${item.name}" from this list`,
                    description: 'Another folder still links to it, so it was not deleted.',
                })
                actions.itemChanged()
                return
            }
            const undoable = deleted.filter((entry) => entry.can_undo && !!entry.ref)
            toast.success({
                title: `Deleted "${item.name}"`,
                action: undoable.length
                    ? {
                          label: 'Undo',
                          onClick: async () => {
                              try {
                                  await api.fileSystem.undoDelete(
                                      undoable.map((entry) => ({
                                          type: entry.type,
                                          ref: entry.ref as string,
                                          ...(entry.path !== undefined ? { path: entry.path } : {}),
                                      }))
                                  )
                                  toast.success({ title: `Restored "${item.name}"` })
                                  actions.itemChanged()
                              } catch {
                                  toast.error({ title: `Couldn't restore "${item.name}". Try again.` })
                              }
                          },
                      }
                    : undefined,
            })
            actions.itemChanged()
        },
    })),
])
