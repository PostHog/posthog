/**
 * The analytics items and collections a person starred. Stars are the project tree's shortcuts, so a star
 * made here shows in every other place that lists them, and the reverse.
 */
export const analyticsStarredLogic = kea<analyticsStarredLogicType>([
    path(['scenes', 'analytics', 'analyticsStarredLogic']),
    connect(() => ({
        values: [projectTreeDataLogic, ['shortcutData', 'shortcutDataLoading']],
        actions: [
            projectTreeDataLogic,
            [
                'addShortcutItem',
                'addShortcutItemSuccess',
                'addShortcutItemFailure',
                'deleteShortcut',
                'deleteShortcutSuccess',
                'deleteShortcutFailure',
            ],
        ],
    })),
    actions({
        toggleStarred: (target: StarTarget) => ({ target }),
    }),
    selectors({
        starredAnalytics: [
            (s) => [s.shortcutData],
            (shortcutData: FileSystemEntry[]): StarredAnalytics[] =>
                shortcutData.flatMap((shortcut): StarredAnalytics[] => {
                    if (!shortcut.id || !shortcut.ref) {
                        return []
                    }
                    // A folder shortcut's `path` is its display name; `ref` holds the folder it points at.
                    if (shortcut.type === 'folder') {
                        return isSpacePath(shortcut.ref)
                            ? [
                                  {
                                      kind: 'collection',
                                      key: starKey('folder', shortcut.ref),
                                      shortcutId: shortcut.id,
                                      path: shortcut.ref,
                                      name: fileSystemEntryName({ path: shortcut.ref }),
                                  },
                              ]
                            : []
                    }
                    const item = fileSystemEntryToAnalytics(shortcut)
                    return item
                        ? [{ kind: 'item', key: starKey(item.type, item.id), shortcutId: shortcut.id, item }]
                        : []
                }),
        ],
        starredShortcutIds: [
            (s) => [s.starredAnalytics],
            (starredAnalytics: StarredAnalytics[]): Map<string, string> =>
                new Map(starredAnalytics.map((starred) => [starred.key, starred.shortcutId])),
        ],
        starredCollectionPaths: [
            (s) => [s.starredAnalytics],
            (starredAnalytics: StarredAnalytics[]): Set<string> =>
                new Set(starredAnalytics.flatMap((starred) => (starred.kind === 'collection' ? [starred.path] : []))),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        toggleStarred: ({ target }) => {
            // Every star control is disabled while a change saves. This also stops a repeated dispatch.
            if (values.shortcutDataLoading) {
                return
            }
            cache.collectionToggled = target.type === 'folder'
            const shortcutId = values.starredShortcutIds.get(starKey(target.type, target.ref))
            if (shortcutId) {
                actions.deleteShortcut(shortcutId)
            } else if (target.type === 'folder') {
                // A folder shortcut keeps its path as ref, so a rename moves the star with the folder.
                actions.addShortcutItem({ path: target.ref, type: 'folder' } as FileSystemEntry)
            } else {
                actions.addShortcutItem({
                    path: escapePath(target.name),
                    type: target.type,
                    ref: target.ref,
                    href: target.href,
                } as FileSystemEntry)
            }
        },
        addShortcutItemSuccess: () => {
            if (cache.collectionToggled) {
                cache.collectionToggled = false
                // pinned: analytics event name and property. Renaming them breaks dashboards.
                posthog.capture('analytics collection pinned', { pinned_count: values.starredCollectionPaths.size })
            }
        },
        deleteShortcutSuccess: () => {
            if (cache.collectionToggled) {
                cache.collectionToggled = false
                // pinned: analytics event name and property. Renaming them breaks dashboards.
                posthog.capture('analytics collection pinned', { pinned_count: values.starredCollectionPaths.size })
            }
        },
        addShortcutItemFailure: () => {
            cache.collectionToggled = false
        },
        deleteShortcutFailure: () => {
            cache.collectionToggled = false
        },
    })),
])
