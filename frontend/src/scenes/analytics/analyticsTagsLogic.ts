import { MakeLogicType, actions, kea, listeners, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { toast } from '@posthog/quill'

import { teamLogic } from 'scenes/teamLogic'

import { dashboardsPartialUpdate } from 'products/dashboards/frontend/generated/api'
import { insightsPartialUpdate } from 'products/product_analytics/frontend/generated/api'

import type { TaggableAnalyticsType } from './analyticsFeed'

export interface AnalyticsTagTarget {
    type: TaggableAnalyticsType
    /** A dashboard's id or an insight's short id, as the file system row holds it. */
    ref: string
    name: string
    tags: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsTagsLogicValues {
    draftTags: string[]
    hasChanges: boolean
    saving: boolean
    target: AnalyticsTagTarget | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsTagsLogicActions {
    closeTagEditor: () => {
        value: true
    }
    openTagEditor: (target: AnalyticsTagTarget) => {
        target: AnalyticsTagTarget
    }
    saveTags: () => {
        value: true
    }
    saveTagsFailure: () => {
        value: true
    }
    setDraftTags: (tags: string[]) => {
        tags: string[]
    }
    tagsSaved: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsTagsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        hasChanges: (target: AnalyticsTagTarget | null, draftTags: string[]) => boolean
    }
}

export type analyticsTagsLogicType = MakeLogicType<
    analyticsTagsLogicValues,
    analyticsTagsLogicActions,
    Record<string, any>,
    analyticsTagsLogicMeta
>

export const analyticsTagsLogic = kea<analyticsTagsLogicType>([
    path(['scenes', 'analytics', 'analyticsTagsLogic']),
    actions({
        openTagEditor: (target: AnalyticsTagTarget) => ({ target }),
        closeTagEditor: true,
        setDraftTags: (tags: string[]) => ({ tags }),
        saveTags: true,
        tagsSaved: true,
        saveTagsFailure: true,
    }),
    reducers({
        target: [
            null as AnalyticsTagTarget | null,
            {
                openTagEditor: (_, { target }) => target,
                closeTagEditor: () => null,
                tagsSaved: () => null,
            },
        ],
        draftTags: [
            [] as string[],
            {
                openTagEditor: (_, { target }) => target.tags,
                setDraftTags: (_, { tags }) => tags,
            },
        ],
        saving: [
            false,
            {
                saveTags: () => true,
                tagsSaved: () => false,
                saveTagsFailure: () => false,
            },
        ],
    }),
    selectors({
        hasChanges: [
            (s) => [s.target, s.draftTags],
            (target: AnalyticsTagTarget | null, draftTags: string[]): boolean =>
                !!target &&
                (draftTags.length !== target.tags.length || draftTags.some((tag) => !target.tags.includes(tag))),
        ],
    }),
    listeners(({ actions, values }) => ({
        openTagEditor: ({ target }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics tags editor opened', { type: target.type, tag_count: target.tags.length })
        },
        saveTags: async () => {
            const target = values.target
            if (!target) {
                return
            }
            const projectId = String(teamLogic.values.currentTeamId)
            const tags = values.draftTags
            try {
                if (target.type === 'dashboard') {
                    await dashboardsPartialUpdate(projectId, Number(target.ref), { tags })
                } else {
                    await insightsPartialUpdate(projectId, target.ref, { tags })
                }
            } catch {
                actions.saveTagsFailure()
                toast.error({ title: "Couldn't save the tags. Try again." })
                return
            }
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics tags saved', {
                type: target.type,
                tag_count: tags.length,
                previous_tag_count: target.tags.length,
            })
            actions.tagsSaved()
        },
    })),
])
