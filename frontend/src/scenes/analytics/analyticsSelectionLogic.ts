/** The rows picked in the Analytics list, and the changes the person makes to all of them at once. */
export const analyticsSelectionLogic = kea<analyticsSelectionLogicType>([
    path(['scenes', 'analytics', 'analyticsSelectionLogic']),
    connect(() => ({
        values: [analyticsListLogic, ['items'], projectLogic, ['currentProjectId']],
        actions: [
            analyticsListLogic,
            ['loadList', 'setScope', 'setFiltersFromUrl'],
            analyticsShareLogic,
            ['itemsMoved'],
        ],
    })),
    actions({
        setRowSelection: (rowSelection: RowSelectionState) => ({ rowSelection }),
        clearSelection: true,
        openBulkTags: (action: AnalyticsBulkTagAction) => ({ action }),
        closeBulkTags: true,
        applyBulkTags: (tags: string[]) => ({ tags }),
        bulkTagsDone: true,
        bulkTagsFailed: true,
    }),
    reducers({
        rowSelection: [
            {} as RowSelectionState,
            {
                setRowSelection: (_, { rowSelection }) => rowSelection,
                clearSelection: () => ({}),
                // Another scope or folder lists other rows, so a selection made on the last one does not carry over.
                setScope: () => ({}),
                setFiltersFromUrl: () => ({}),
            },
        ],
        bulkTagsAction: [
            null as AnalyticsBulkTagAction | null,
            {
                openBulkTags: (_, { action }) => action,
                closeBulkTags: () => null,
                bulkTagsDone: () => null,
            },
        ],
        bulkTagsSaving: [
            false,
            {
                applyBulkTags: () => true,
                bulkTagsDone: () => false,
                bulkTagsFailed: () => false,
                closeBulkTags: () => false,
            },
        ],
    }),
    selectors({
        // A selected row that a reload or a filter took away does not count, so the bar never acts on a hidden item.
        selectedItems: [
            (s) => [s.items, s.rowSelection],
            (items: AnalyticsItem[], rowSelection: RowSelectionState): AnalyticsItem[] =>
                items.filter((item) => rowSelection[analyticsItemRowId(item)]),
        ],
        taggableSelectedItems: [
            (s) => [s.selectedItems],
            (selectedItems: AnalyticsItem[]): AnalyticsItem[] =>
                selectedItems.filter((item) => TAGGABLE_ANALYTICS_TYPES.has(item.type)),
        ],
        selectedTags: [
            (s) => [s.taggableSelectedItems],
            (items: AnalyticsItem[]): string[] => [...new Set(items.flatMap((item) => item.tags))].sort(),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setRowSelection: ({ rowSelection }) => {
            const selecting = Object.values(rowSelection).some(Boolean)
            if (selecting && !cache.selecting) {
                // pinned: analytics event name and properties. Renaming them breaks dashboards.
                posthog.capture('analytics items selected', { mode: analyticsListLogic.values.mode })
            }
            cache.selecting = selecting
        },
        clearSelection: () => {
            cache.selecting = false
        },
        itemsMoved: () => actions.clearSelection(),
        applyBulkTags: async ({ tags }) => {
            const action = values.bulkTagsAction
            const items = values.taggableSelectedItems
            if (!action || !tags.length || !items.length) {
                actions.bulkTagsFailed()
                return
            }
            const projectId = String(values.currentProjectId)
            try {
                const dashboardIds = items.filter((item) => item.type === 'dashboard').map((item) => Number(item.id))
                // The list knows an insight by its short id, and the bulk endpoint takes the numeric one.
                const insightIds = (
                    await Promise.all(
                        items
                            .filter((item) => item.type === 'insight')
                            .map(
                                async (item) =>
                                    (await insightsList(projectId, { short_id: item.id, basic: true, limit: 1 }))
                                        .results[0]?.id
                            )
                    )
                ).filter((id): id is number => typeof id === 'number')
                const responses = await Promise.all([
                    ...chunk(dashboardIds).map((ids) =>
                        dashboardsBulkUpdateTagsCreate(projectId, { ids, action, tags })
                    ),
                    ...chunk(insightIds).map((ids) => insightsBulkUpdateTagsCreate(projectId, { ids, action, tags })),
                ])
                const updated = responses.reduce((sum, response) => sum + response.updated.length, 0)
                const skipped = items.length - updated
                const tagLabel = tags.length === 1 ? `"${tags[0]}"` : pluralize(tags.length, 'tag')
                const title =
                    action === 'add'
                        ? `Added ${tagLabel} to ${pluralize(updated, 'item')}`
                        : `Removed ${tagLabel} from ${pluralize(updated, 'item')}`
                if (skipped) {
                    toast.warning({
                        title,
                        description: `${pluralize(skipped, 'item')} didn’t change because you can’t edit ${
                            skipped === 1 ? 'it' : 'them'
                        }.`,
                    })
                } else {
                    toast.success({ title })
                }
                // pinned: analytics event name and properties. Renaming them breaks dashboards.
                posthog.capture('analytics items tagged', {
                    action,
                    tag_count: tags.length,
                    item_count: items.length,
                    updated_count: updated,
                })
                actions.bulkTagsDone()
                actions.clearSelection()
                actions.loadList()
            } catch {
                toast.error({
                    title: 'Couldn’t update the tags. Try again, and if it keeps happening contact support.',
                })
                actions.bulkTagsFailed()
            }
        },
    })),
])
