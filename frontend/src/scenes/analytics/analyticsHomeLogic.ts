import { MakeLogicType, connect, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { urlToAction } from 'kea-router'

import api from 'lib/api'
import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { urls } from 'scenes/urls'

import { FileSystemEntry } from '~/queries/schema/schema-general'

import { AnalyticsItem, fileSystemEntryToAnalytics } from './analyticsUtils'

export const ANALYTICS_HOME_RECENT_LIMIT = 5
// The view log also records every page visit as a `scene` row and the API excludes one type at a
// time, so the page asks for a wide window and keeps the analytics rows itself.
const RECENTS_FETCH_LIMIT = 50

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsHomeLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    recentAnalytics: AnalyticsItem[]
    recentEntries: FileSystemEntry[] | null
    recentEntriesLoading: boolean
    recentsFailed: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsHomeLogicActions {
    loadRecentEntries: (_: void) => void
    loadRecentEntriesFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadRecentEntriesSuccess: (
        recentEntries: FileSystemEntry[],
        payload?: void
    ) => {
        recentEntries: FileSystemEntry[]
        payload?: void
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsHomeLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        recentAnalytics: (recentEntries: FileSystemEntry[] | null) => AnalyticsItem[]
    }
}

export type analyticsHomeLogicType = MakeLogicType<
    analyticsHomeLogicValues,
    analyticsHomeLogicActions,
    Record<string, any>,
    analyticsHomeLogicMeta
>

export const analyticsHomeLogic = kea<analyticsHomeLogicType>([
    path(['scenes', 'analytics', 'analyticsHomeLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),
    loaders(() => ({
        // Null until the first answer, so the page can tell "not loaded yet" from "nothing opened yet".
        recentEntries: [
            null as FileSystemEntry[] | null,
            {
                loadRecentEntries: async (_: void, breakpoint) => {
                    const response = await api.fileSystem.list({
                        orderBy: '-last_viewed_at',
                        notType: 'scene',
                        limit: RECENTS_FETCH_LIMIT,
                    })
                    breakpoint()
                    return response.results
                },
            },
        ],
    })),
    reducers({
        recentsFailed: [
            false,
            {
                loadRecentEntries: () => false,
                loadRecentEntriesFailure: () => true,
            },
        ],
    }),
    selectors({
        recentAnalytics: [
            (s) => [s.recentEntries],
            (recentEntries: FileSystemEntry[] | null): AnalyticsItem[] =>
                (recentEntries ?? [])
                    .flatMap((entry) => {
                        const item = fileSystemEntryToAnalytics(entry)
                        return item ? [item] : []
                    })
                    .slice(0, ANALYTICS_HOME_RECENT_LIMIT),
        ],
    }),
    urlToAction(({ actions, values }) => ({
        [urls.analytics()]: () => {
            // The scene renders nothing without the flag, so it must not load anything either.
            if (values.featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV]) {
                // Opening something elsewhere changes the list, so each visit reloads it.
                actions.loadRecentEntries()
            }
        },
    })),
])
