import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { spaceLabel } from '~/layout/today/todaySpacesLogic'

import { taskChannelsList } from 'products/tasks/frontend/generated/api'
import type { ChannelDTOApi } from 'products/tasks/frontend/generated/api.schemas'

import {
    AnalyticsFeed,
    AnalyticsFeedQuery,
    AnalyticsSourcePage,
    AnalyticsSourceState,
    analyticsFeedFromSources,
    analyticsFeedTypes,
    analyticsSourceKey,
    fetchAnalyticsSourcePage,
    mergeAnalyticsSources,
} from './analyticsFeed'
import { AnalyticsType } from './analyticsUtils'

const MAX_FILTERED_SOURCES = 30

interface AnalyticsFeedSnapshot {
    sources: Record<string, AnalyticsSourceState>
    spaceNames: Record<string, string>
}

let snapshot: AnalyticsFeedSnapshot | null = null

export function resetAnalyticsFeedSnapshot(): void {
    snapshot = null
}

function settledSources(sources: Record<string, AnalyticsSourceState>): Record<string, AnalyticsSourceState> {
    return Object.fromEntries(
        Object.entries(sources)
            .filter(([, source]) => source.initialized)
            .map(([key, source]) => [key, { ...source, refreshing: false, loading: false }])
    )
}

function isFiltered(query: AnalyticsFeedQuery): boolean {
    return !!query.search.trim() || !!query.createdBy || query.tags.length > 0
}

// Every search or filter combination is its own set of sources, so old ones are dropped to bound memory.
function withoutOldFiltered(sources: Record<string, AnalyticsSourceState>): Record<string, AnalyticsSourceState> {
    const filteredKeys = Object.keys(sources).filter((key) => isFiltered(sources[key].query))
    const dropped = new Set(filteredKeys.slice(0, Math.max(0, filteredKeys.length - MAX_FILTERED_SOURCES)))
    return dropped.size ? Object.fromEntries(Object.entries(sources).filter(([key]) => !dropped.has(key))) : sources
}

export function selectAnalyticsFeed(
    sources: Record<string, AnalyticsSourceState>,
    spaceNames: Record<string, string>,
    projectId: number | null,
    query: AnalyticsFeedQuery
): AnalyticsFeed {
    return analyticsFeedFromSources(
        analyticsFeedTypes(query).map((type) =>
            projectId ? sources[analyticsSourceKey(String(projectId), query, type)] : undefined
        ),
        spaceNames
    )
}

