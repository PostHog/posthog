export type analyticsFeedLogicType = MakeLogicType<analyticsFeedLogicValues, analyticsFeedLogicActions>

/**
 * The project's analytics, paged per type and merged newest first. Shared by the list page, the sidebar
 * and the home page, so each query is fetched once and a revisit shows rows at once.
 */
export const analyticsFeedLogic = kea<analyticsFeedLogicType>([
    path(['scenes', 'analytics', 'analyticsFeedLogic']),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        ensureFeed: (query: AnalyticsFeedQuery, count: number) => ({ query, count }),
        refreshFeed: (query: AnalyticsFeedQuery) => ({ query }),
        refreshSource: (key: string, projectId: string, query: AnalyticsFeedQuery, type: AnalyticsType) => ({
            key,
            projectId,
            query,
            type,
        }),
        sourceRefreshed: (key: string, generation: number, page: AnalyticsSourcePage | null) => ({
            key,
            generation,
            page,
        }),
        loadSourcePage: (key: string) => ({ key }),
        sourcePageLoaded: (key: string, generation: number, offset: number, page: AnalyticsSourcePage | null) => ({
            key,
            generation,
            offset,
            page,
        }),
        restoreSnapshot: (snapshot: AnalyticsFeedSnapshot) => ({ snapshot }),
    }),
    loaders(({ values }) => ({
        spaceNames: [
            {} as Record<string, string>,
            {
                loadSpaceNames: async () => {
                    if (!values.currentTeamId) {
                        return values.spaceNames
                    }
                    try {
                        const response = await taskChannelsList(String(values.currentTeamId))
                        // Without `limit` the endpoint answers with a bare array rather than a page.
                        const spaces = Array.isArray(response) ? (response as ChannelDTOApi[]) : response.results
                        return Object.fromEntries(spaces.map((space) => [space.id, spaceLabel(space)]))
                    } catch {
                        return values.spaceNames
                    }
                },
            },
        ],
    })),
    reducers({
        spaceNames: {
            restoreSnapshot: (state, { snapshot }) => (Object.keys(state).length ? state : snapshot.spaceNames),
        },
        sources: [
            {} as Record<string, AnalyticsSourceState>,
            {
                restoreSnapshot: (state, { snapshot }) => ({ ...snapshot.sources, ...state }),
                refreshSource: (state, { key, projectId, query, type }) => {
                    const { [key]: current, ...rest } = state
                    return withoutOldFiltered({
                        ...rest,
                        [key]: current
                            ? { ...current, refreshing: true, generation: current.generation + 1 }
                            : {
                                  projectId,
                                  query,
                                  type,
                                  items: [],
                                  offset: 0,
                                  hasMore: true,
                                  initialized: false,
                                  refreshing: true,
                                  loading: false,
                                  failed: false,
                                  generation: 1,
                              },
                    })
                },
                sourceRefreshed: (state, { key, generation, page }) => {
                    const current = state[key]
                    if (!current || current.generation !== generation) {
                        return state
                    }
                    const next: AnalyticsSourceState = page
                        ? {
                              ...current,
                              items: page.items,
                              offset: page.fetched,
                              hasMore: page.hasMore,
                              initialized: true,
                              refreshing: false,
                              loading: false,
                              failed: false,
                          }
                        : current.initialized
                          ? { ...current, refreshing: false, failed: true }
                          : { ...current, hasMore: false, initialized: true, refreshing: false, failed: true }
                    return { ...state, [key]: next }
                },
                loadSourcePage: (state, { key }) =>
                    state[key] ? { ...state, [key]: { ...state[key], loading: true } } : state,
                sourcePageLoaded: (state, { key, generation, offset, page }) => {
                    const current = state[key]
                    if (!current || current.generation !== generation || current.offset !== offset) {
                        return state
                    }
                    if (!page) {
                        return { ...state, [key]: { ...current, loading: false, hasMore: false, failed: true } }
                    }
                    const known = new Set(current.items.map((item) => item.id))
                    return {
                        ...state,
                        [key]: {
                            ...current,
                            items: [...current.items, ...page.items.filter((item) => !known.has(item.id))],
                            offset: current.offset + page.fetched,
                            hasMore: page.hasMore,
                            loading: false,
                        },
                    }
                },
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        refreshFeed: ({ query }) => {
            if (!values.currentTeamId) {
                return
            }
            const projectId = String(values.currentTeamId)
            for (const type of analyticsFeedTypes(query)) {
                const key = analyticsSourceKey(projectId, query, type)
                if (!values.sources[key]?.refreshing) {
                    actions.refreshSource(key, projectId, { ...query, search: query.search.trim() }, type)
                }
            }
        },
        ensureFeed: ({ query, count }) => {
            if (!values.currentTeamId) {
                return
            }
            const projectId = String(values.currentTeamId)
            const keys = analyticsFeedTypes(query).map((type) => analyticsSourceKey(projectId, query, type))
            if (keys.some((key) => !values.sources[key])) {
                actions.refreshFeed(query)
                return
            }
            const { items, blocking } = mergeAnalyticsSources(keys.map((key) => values.sources[key]))
            if (items.length >= count) {
                return
            }
            for (const source of blocking) {
                if (source.initialized && !source.loading && !source.refreshing) {
                    actions.loadSourcePage(analyticsSourceKey(source.projectId, source.query, source.type))
                }
            }
        },
        refreshSource: async ({ key, projectId, query, type }) => {
            const generation = values.sources[key].generation
            const page = await fetchAnalyticsSourcePage(projectId, type, query, 0).catch(() => null)
            actions.sourceRefreshed(key, generation, page)
        },
        loadSourcePage: async ({ key }) => {
            const source = values.sources[key]
            if (!source) {
                return
            }
            const { generation, offset } = source
            const page = await fetchAnalyticsSourcePage(source.projectId, source.type, source.query, offset).catch(
                () => null
            )
            actions.sourcePageLoaded(key, generation, offset, page)
        },
    })),
    afterMount(({ actions }) => {
        if (snapshot) {
            actions.restoreSnapshot(snapshot)
        }
        actions.loadSpaceNames()
    }),
    beforeUnmount(({ values }) => {
        snapshot = { sources: settledSources(values.sources), spaceNames: values.spaceNames }
    }),
])
