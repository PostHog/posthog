export type AddToCollectionTab = 'mine' | 'all'

// Each move is its own request, so a long selection goes out a few at a time.
const MOVE_CONCURRENCY = 5

export function addToCollectionItemKey(item: Pick<AnalyticsItem, 'type' | 'id'>): string {
    return `${item.type}:${item.id}`
}

function parentFolder(path: string): string {
    return joinPath(splitPath(path).slice(0, -1))
}

async function moveIntoFolder(item: AnalyticsItem, folder: string): Promise<void> {
    if (!item.entry) {
        throw new Error(`Couldn’t find where "${item.name}" is saved.`)
    }
    if (item.type === 'canvas') {
        await assertCanvasShareable(item.id)
    }
    await api.fileSystem.move(item.entry.id, `${folder}/${escapePath(item.name)}`)
}

