/** Picks existing work, the person's own or anyone's, and moves it into the collection or folder that is open. */
export const addToCollectionLogic = kea<addToCollectionLogicType>([
    path(['scenes', 'analytics', 'addToCollectionLogic']),
    connect(() => ({
        values: [userLogic, ['user'], analyticsFeedLogic, ['sources', 'currentTeamId']],
        actions: [analyticsFeedLogic, ['ensureFeed', 'refreshFeed'], analyticsSpacesLogic, ['refreshSpaces']],
    })),
    actions({
        openAddToCollection: (folder: string) => ({ folder }),
        closeAddToCollection: true,
        setTab: (tab: AddToCollectionTab) => ({ tab }),
        setSearch: (search: string) => ({ search }),
        loadMore: true,
        toggleItem: (item: AnalyticsItem) => ({ item }),
        addSelected: true,
        addFinished: (failed: AnalyticsItem[]) => ({ failed }),
        itemsAdded: true,
    }),
    reducers({
        folder: [
            null as string | null,
            {
                openAddToCollection: (_, { folder }) => folder,
                closeAddToCollection: () => null,
            },
        ],
        tab: ['mine' as AddToCollectionTab, { openAddToCollection: () => 'mine', setTab: (_, { tab }) => tab }],
        search: ['', { openAddToCollection: () => '', setSearch: (_, { search }) => search }],
        requestedCount: [
            ANALYTICS_FEED_PAGE_SIZE as number,
            {
                openAddToCollection: () => ANALYTICS_FEED_PAGE_SIZE,
                setTab: () => ANALYTICS_FEED_PAGE_SIZE,
                setSearch: () => ANALYTICS_FEED_PAGE_SIZE,
                loadMore: (count) => count + ANALYTICS_FEED_PAGE_SIZE,
            },
        ],
        // Kept across tabs and searches, so a person can pick from both lists before adding.
        selected: [
            {} as Record<string, AnalyticsItem>,
            {
                openAddToCollection: () => ({}),
                toggleItem: (state, { item }) => {
                    const key = addToCollectionItemKey(item)
                    if (state[key]) {
                        const { [key]: _, ...rest } = state
                        return rest
                    }
                    return { ...state, [key]: item }
                },
                addFinished: (_, { failed }) =>
                    Object.fromEntries(failed.map((item) => [addToCollectionItemKey(item), item])),
            },
        ],
        adding: [false, { addSelected: () => true, addFinished: () => false, closeAddToCollection: () => false }],
    }),
    selectors({
        folderName: [
            (s) => [s.folder],
            (folder: string | null): string => (folder ? fileSystemEntryName({ path: folder }) : ''),
        ],
        feedQuery: [
            (s) => [s.tab, s.search, s.user],
            (tab: AddToCollectionTab, search: string, user: null | import('~/types').UserType): AnalyticsFeedQuery => {
                const mine = tab === 'mine' && !!user
                return {
                    ...EMPTY_ANALYTICS_FEED_QUERY,
                    orderBy: '-last_viewed_at',
                    search,
                    // The feed keys its cached pages on the creators, so "My work" needs the uuid as well as the
                    // server filter to stay apart from "View all".
                    createdBy: mine ? [user.uuid] : [],
                    createdByMe: mine,
                }
            },
        ],
        feed: [
            (s) => [s.sources, s.currentTeamId, s.feedQuery],
            (
                sources: Record<string, import('./analyticsFeed').AnalyticsSourceState>,
                currentTeamId: number | null,
                feedQuery: AnalyticsFeedQuery
            ): AnalyticsFeed => selectAnalyticsFeed(sources, currentTeamId, feedQuery),
        ],
        selectedCount: [
            (s) => [s.selected],
            (selected: Record<string, AnalyticsItem>): number => Object.keys(selected).length,
        ],
        addDisabledReason: [
            (s) => [s.selectedCount],
            (selectedCount: number): string | null => (selectedCount ? null : 'Pick at least one item first'),
        ],
    }),
    listeners(({ actions, values }) => ({
        openAddToCollection: ({ folder }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics add items opened', { nested: splitPath(folder).length > 1 })
            // Items move in and out from other pages, so each open reads the lists again.
            actions.refreshFeed(values.feedQuery)
        },
        setTab: () => actions.ensureFeed(values.feedQuery, values.requestedCount),
        setSearch: async (_, breakpoint) => {
            await breakpoint(250)
            actions.ensureFeed(values.feedQuery, values.requestedCount)
        },
        loadMore: () => actions.ensureFeed(values.feedQuery, values.requestedCount),
        addSelected: async () => {
            const folder = values.folder
            const items = Object.values(values.selected)
            if (!folder || !items.length) {
                return
            }
            const failed: AnalyticsItem[] = []
            const errors: string[] = []
            for (let start = 0; start < items.length; start += MOVE_CONCURRENCY) {
                const batch = items.slice(start, start + MOVE_CONCURRENCY)
                const results = await Promise.allSettled(batch.map((item) => moveIntoFolder(item, folder)))
                results.forEach((result, index) => {
                    if (result.status === 'rejected') {
                        failed.push(batch[index])
                        errors.push(result.reason instanceof Error ? result.reason.message : '')
                    }
                })
            }
            const added = items.length - failed.length
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics items added to collection', {
                added,
                failed: failed.length,
                types: [...new Set(items.map((item) => item.type))],
                nested: splitPath(folder).length > 1,
            })
            actions.addFinished(failed)
            if (added) {
                actions.refreshSpaces()
                actions.itemsAdded()
            }
            if (!failed.length) {
                toast.success({ title: `Added ${pluralize(added, 'item')} to ${values.folderName}` })
                actions.closeAddToCollection()
                return
            }
            toast.error({
                title: added
                    ? `Added ${added} of ${pluralize(items.length, 'item')}. The rest are still selected.`
                    : `Couldn’t add ${pluralize(failed.length, 'item')}`,
                description: errors.find(Boolean) ?? 'Try again, or add them from their own pages.',
            })
        },
    })),
])

/** Whether an item already sits directly in the folder, so adding it again would do nothing. */
export function isInFolder(item: AnalyticsItem, folder: string | null): boolean {
    return !!folder && !!item.entry && parentFolder(item.entry.path) === folder
}
