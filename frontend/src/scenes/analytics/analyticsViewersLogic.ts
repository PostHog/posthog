import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { teamLogic } from 'scenes/teamLogic'

import { fileSystemViewersRetrieve } from '~/generated/core/api'
import type { FileSystemViewersApi } from '~/generated/core/api.schemas'

import { AnalyticsType } from './analyticsUtils'

export interface AnalyticsViewersTarget {
    type: AnalyticsType
    ref: string
    name: string
}

/** Where the person opened the viewers from: a count in the list, or the row's menu. */
export type AnalyticsViewersSource = 'views' | 'viewers' | 'menu'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsViewersLogicValues {
    currentProjectId: number | string // teamLogic
    target: AnalyticsViewersTarget | null
    viewers: FileSystemViewersApi | null
    viewersFailed: boolean
    viewersLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analyticsViewersLogicActions {
    closeViewers: () => {
        value: true
    }
    loadViewers: (_: void) => void
    loadViewersFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadViewersSuccess: (
        viewers: FileSystemViewersApi | null,
        payload?: void
    ) => {
        viewers: FileSystemViewersApi | null
        payload?: void
    }
    openViewers: (
        target: AnalyticsViewersTarget,
        source: AnalyticsViewersSource
    ) => {
        source: AnalyticsViewersSource
        target: AnalyticsViewersTarget
    }
}

export type analyticsViewersLogicType = MakeLogicType<analyticsViewersLogicValues, analyticsViewersLogicActions>

/** Who viewed one item in the last 30 days, shown in a dialog over the Analytics list. */
export const analyticsViewersLogic = kea<analyticsViewersLogicType>([
    path(['scenes', 'analytics', 'analyticsViewersLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),
    actions({
        openViewers: (target: AnalyticsViewersTarget, source: AnalyticsViewersSource) => ({ target, source }),
        closeViewers: true,
    }),
    reducers({
        target: [
            null as AnalyticsViewersTarget | null,
            {
                openViewers: (_, { target }) => target,
                closeViewers: () => null,
            },
        ],
        viewersFailed: [
            false,
            {
                loadViewers: () => false,
                loadViewersFailure: () => true,
            },
        ],
    }),
    loaders(({ values }) => ({
        viewers: [
            null as FileSystemViewersApi | null,
            {
                loadViewers: async (_: void, breakpoint) => {
                    const target = values.target
                    if (!target) {
                        return null
                    }
                    const viewers = await fileSystemViewersRetrieve(String(values.currentProjectId), {
                        type: target.type,
                        ref: target.ref,
                    })
                    breakpoint()
                    return viewers
                },
            },
        ],
    })),
    reducers({
        // A dialog opened on another item never shows the last item's viewers while its own viewers load.
        viewers: {
            openViewers: () => null,
        },
    }),
    listeners(({ actions }) => ({
        openViewers: ({ target, source }) => {
            // pinned: analytics event name and properties. Renaming them breaks dashboards.
            posthog.capture('analytics viewers opened', { object_type: target.type, source })
            actions.loadViewers()
        },
    })),
])
