export const nodeDetailSceneLogic = kea<nodeDetailSceneLogicType>([
    props({} as NodeDetailSceneLogicProps),
    key((props) => props.id),
    path((key) => ['scenes', 'models', 'nodeDetailSceneLogic', key]),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
        actions: [dataWarehouseViewsLogic, ['updateDataWarehouseSavedQuerySuccess']],
    })),
    actions({
        updateNodeDescription: (description: string) => ({ description }),
        setCurrentTab: (tab: NodeDetailSceneTab | null) => ({ tab }),
        canonicalizeTab: true,
        openLineageModal: true,
        closeLineageModal: true,
    }),
    reducers({
        // What the address bar asks for. Tab links navigate, so nothing else may write this.
        currentTab: [
            null as NodeDetailSceneTab | null,
            {
                setCurrentTab: (_, { tab }) => tab,
            },
        ],
        // Panels mount on first visit and then stay mounted, so keyed logics under them keep their
        // drafts and viewports across tab switches.
        visitedTabs: [
            [] as NodeDetailSceneTab[],
            {
                setCurrentTab: (state, { tab }) => (!tab || state.includes(tab) ? state : [...state, tab]),
            },
        ],
        savedQuerySettled: [
            false,
            {
                loadSavedQuerySuccess: () => true,
                loadSavedQueryFailure: () => true,
            },
        ],
        savedQueryError: [
            false,
            {
                loadSavedQuery: () => false,
                loadSavedQuerySuccess: () => false,
                loadSavedQueryFailure: () => true,
            },
        ],
        lineageGraphError: [
            false,
            {
                loadLineageGraph: () => false,
                loadLineageGraphSuccess: () => false,
                loadLineageGraphFailure: () => true,
            },
        ],
        lineageModalOpen: [
            false,
            {
                openLineageModal: () => true,
                closeLineageModal: () => false,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        node: {
            __default: null as DataModelingNode | null,
            loadNode: async () => {
                return await api.dataModelingNodes.get(props.id)
            },
            updateNodeDescription: async ({ description }) => {
                const updated = await api.dataModelingNodes.update(props.id, { description })
                return updated
            },
        },
        savedQuery: {
            __default: null as DataWarehouseSavedQuery | null,
            loadSavedQuery: async () => {
                const node = values.node
                if (!node?.saved_query_id) {
                    return null
                }
                return await api.dataWarehouseSavedQueries.get(node.saved_query_id)
            },
        },
        lineageGraph: {
            __default: null as LineageGraphData | null,
            loadLineageGraph: async () => {
                const node = values.node
                if (!node) {
                    return null
                }
                const { nodes, edges } = await api.dataModelingNodes.lineage({ nodeId: node.id })
                return { nodes, edges, currentNodeId: node.id }
            },
        },
    })),
    selectors({
        breadcrumbs: [
            (s) => [s.node],
            (node: DataModelingNode | null): Breadcrumb[] => [
                {
                    key: 'Models',
                    name: 'Models',
                    path: urls.models(),
                },
                {
                    key: ['NodeDetail', node?.id || 'loading'],
                    name: node?.name || 'Loading...',
                },
            ],
        ],
        nodeType: [(s) => [s.node], (node: DataModelingNode | null) => node?.type ?? null],
        // Which tabs exist depends on the saved query too, so a node that has one is only resolved
        // once that request settles. Deciding earlier renders a tab bar we then have to change.
        sceneResolved: [
            (s) => [s.node, s.savedQuerySettled],
            (node: DataModelingNode | null, savedQuerySettled: boolean): boolean =>
                !!node && (!node.saved_query_id || savedQuerySettled),
        ],
        availableTabs: [
            (s) => [s.node, s.sceneResolved, s.featureFlags],
            (
                node: DataModelingNode | null,
                sceneResolved: boolean,
                featureFlags: FeatureFlagsSet
            ): NodeDetailSceneTab[] => {
                if (!sceneResolved || !node) {
                    return []
                }
                const tabs: NodeDetailSceneTab[] = []
                if (node.type !== 'table') {
                    tabs.push('query')
                }
                tabs.push('lineage')
                // Gate on the node's saved_query_id, not the loaded savedQuery, so the tab
                // survives a saved-query load failure and its panel can show the error and retry.
                // Not gated on `is_materialized`: the panel carries its own Materialize call to
                // action, which is how a plain view becomes materialized from this page.
                if (node.saved_query_id) {
                    tabs.push('materialization')
                }
                if (featureFlags[FEATURE_FLAGS.DATA_QUALITY_CHECKS] && node.saved_query_id) {
                    tabs.push('tests')
                }
                return tabs
            },
        ],
        // The saved query is the authority on this, but its request can fail, and the scene still
        // renders once it settles. The node's type carries the same answer, so a failed load falls
        // back to it rather than reading as not materialized -- which would contradict the
        // Materialized view tag beside it and send the default tab to Query.
        isMaterialized: [
            (s) => [s.node, s.savedQuery],
            (node: DataModelingNode | null, savedQuery: DataWarehouseSavedQuery | null): boolean => {
                if (savedQuery) {
                    return !!savedQuery.is_materialized
                }
                return node?.type === 'matview' || node?.type === 'endpoint'
            },
        ],
        defaultTab: [
            (s) => [s.node, s.isMaterialized],
            (node: DataModelingNode | null, isMaterialized: boolean): NodeDetailSceneTab => {
                if (node?.type === 'table') {
                    return 'lineage'
                }
                // An endpoint's saved query is always materialized, but its materialization panel
                // strips most controls, so Query is the tab that fits it.
                if (node?.type === 'endpoint') {
                    return 'query'
                }
                return isMaterialized ? 'materialization' : 'query'
            },
        ],
        effectiveTab: [
            (s) => [s.currentTab, s.availableTabs, s.defaultTab],
            (
                currentTab: NodeDetailSceneTab | null,
                availableTabs: NodeDetailSceneTab[],
                defaultTab: NodeDetailSceneTab
            ): NodeDetailSceneTab | null => {
                if (availableTabs.length === 0) {
                    return null
                }
                if (currentTab && availableTabs.includes(currentTab)) {
                    return currentTab
                }
                return availableTabs.includes(defaultTab) ? defaultTab : availableTabs[0]
            },
        ],
        // The saved query wins over the node: the node's copy only advances on a DAG run, so after
        // a Sync now it still reports the run before it, contradicting the materialization tab.
        effectiveLastRunAt: [
            (s) => [s.node, s.savedQuery],
            (node: DataModelingNode | null, savedQuery: DataWarehouseSavedQuery | null): string | null =>
                savedQuery?.last_run_at ?? node?.last_run_at ?? null,
        ],
        effectiveLastRunStatus: [
            (s) => [s.node, s.savedQuery],
            (node: DataModelingNode | null, savedQuery: DataWarehouseSavedQuery | null): string | null =>
                savedQuery?.status ?? node?.last_run_status ?? null,
        ],
    }),
    listeners(({ actions, props, values }) => ({
        loadNodeSuccess: () => {
            const node = values.node
            if (node?.saved_query_id) {
                actions.loadSavedQuery()
            }
            actions.loadLineageGraph()
            actions.canonicalizeTab()
        },
        loadSavedQuerySuccess: () => actions.canonicalizeTab(),
        loadSavedQueryFailure: () => actions.canonicalizeTab(),
        // The address bar decides which tab shows, so once the data says which tabs exist, a URL
        // asking for one this model has no page for is corrected in place. Replace, not push: a
        // redirect the user did not ask for is not a history step.
        canonicalizeTab: () => {
            const tab = values.effectiveTab
            if (tab && tab !== values.currentTab) {
                router.actions.replace(urls.nodeDetail(props.id, tab))
            }
        },
        updateDataWarehouseSavedQuerySuccess: () => {
            if (values.node?.saved_query_id) {
                actions.loadSavedQuery()
            }
        },
    })),
    urlToAction(({ actions, props }) => {
        // Clicking a node in the lineage graph navigates model to model. The outgoing model's logic
        // is still mounted while the new URL lands, so it must ignore routes for another id.
        const applyTab = (id: string | undefined, tab: unknown): void => {
            if (id !== props.id) {
                return
            }
            actions.setCurrentTab(isNodeDetailSceneTab(tab) ? tab : null)
            actions.canonicalizeTab()
        }

        return {
            [urls.nodeDetail(':id', ':tab' as NodeDetailSceneTab)]: ({ id, tab }) => applyTab(id, tab),
            [urls.nodeDetail(':id')]: ({ id }) => applyTab(id, undefined),
        }
    }),
    afterMount(({ actions }) => {
        actions.loadNode()
    }),
])
