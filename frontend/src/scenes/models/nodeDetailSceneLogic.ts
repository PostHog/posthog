export const NODE_DETAIL_SCENE_TABS = ['query', 'lineage', 'materialization', 'tests'] as const
export type NodeDetailSceneTab = (typeof NODE_DETAIL_SCENE_TABS)[number]

export interface NodeDetailSceneLogicProps {
    id: string
}

export interface LineageGraphData {
    /** DataModelingNode objects in the subgraph (ancestors + current + descendants) */
    nodes: DataModelingNode[]
    /** Edges between nodes in the subgraph */
    edges: DataModelingEdge[]
    /** The current node's ID */
    currentNodeId: string
}

function isNodeDetailSceneTab(tab: unknown): tab is NodeDetailSceneTab {
    return typeof tab === 'string' && (NODE_DETAIL_SCENE_TABS as readonly string[]).includes(tab)
}

