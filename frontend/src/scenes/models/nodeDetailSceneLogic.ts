export const nodeDetailSceneLogic = kea<nodeDetailSceneLogicType>([
    props({} as NodeDetailSceneLogicProps),
    key((props) => props.id),
    path((key) => ['scenes', 'models', 'nodeDetailSceneLogic', key]),
    connect({
        actions: [dataWarehouseViewsLogic, ['updateDataWarehouseSavedQuerySuccess']],
    }),
    actions({
        updateNodeDescription: (description: string) => ({ description }),
        setJobsOffset: (offset: number) => ({ offset }),
        setTab: (tab: NodeDetailTab) => ({ tab }),
        setLineageFilter: (filter: LineageDirectionFilter) => ({ filter }),
        openLineageModal: true,
        closeLineageModal: true,
    }),
    reducers({
        activeTab: [
            'query' as NodeDetailTab,
            {
                setTab: (_, { tab }) => tab,
            },
        ],
        lineageFilter: [
            'all' as LineageDirectionFilter,
            {
                setLineageFilter: (_, { filter }) => filter,
            },
        ],
        jobsOffset: [
            0 as number,
            {
                setJobsOffset: (_, { offset }) => offset,
            },
        ],
        lineageModalOpen: [
            false,
            {
                openLineageModal: () => true,
                closeLineageModal: () => false,
            },
        ],
    }),
    loaders(({ props, values }) => ({
        node: {
            __default: null as DataModelingNode | null,
            loadNode: async () => {
                return await api.dataModelingNodes.get(props.id)
            },
            updateNodeDescription: async ({ description }) => {
                const updated = await api.dataModelingNodes.update(props.id, { description })
                return updated
            },
        },
        savedQuery: {
            __default: null as DataWarehouseSavedQuery | null,
            loadSavedQuery: async () => {
                const node = values.node
                if (!node?.saved_query_id) {
                    return null
                }
                return await api.dataWarehouseSavedQueries.get(node.saved_query_id)
            },
        },
        materializationJobs: {
            __default: null as CountedPaginatedResponse<DataModelingJob> | null,
            loadMaterializationJobs: async () => {
                const savedQuery = values.savedQuery
                if (!savedQuery) {
                    return null
                }
                return await api.dataWarehouseSavedQueries.dataWarehouseDataModelingJobs.list(
                    savedQuery.id,
                    10,
                    values.jobsOffset
                )
            },
        },
        lineageGraph: {
            __default: null as LineageGraphData | null,
            loadLineageGraph: async () => {
                const node = values.node
                if (!node) {
                    return null
                }
                const { nodes, edges } = await api.dataModelingNodes.lineage({ nodeId: node.id })
                return { nodes, edges, currentNodeId: node.id }
            },
        },
    })),
    selectors({
        breadcrumbs: [
            (s) => [s.node],
            (node: DataModelingNode | null): Breadcrumb[] => [
                {
                    key: 'Models',
                    name: 'Models',
                    path: urls.models(),
                },
                {
                    key: ['NodeDetail', node?.id || 'loading'],
                    name: node?.name || 'Loading...',
                },
            ],
        ],
        nodeType: [(s) => [s.node], (node: DataModelingNode | null) => node?.type ?? null],
        lineageDirections: [
            (s) => [s.lineageGraph],
            (graph: LineageGraphData | null): Record<string, LineageDirection> => {
                if (!graph) {
                    return {}
                }
                const parents: Record<string, string[]> = {}
                const children: Record<string, string[]> = {}
                for (const edge of graph.edges) {
                    ;(children[edge.source_id] ??= []).push(edge.target_id)
                    ;(parents[edge.target_id] ??= []).push(edge.source_id)
                }
                const directions: Record<string, LineageDirection> = {}
                const walk = (adjacency: Record<string, string[]>, direction: LineageDirection): void => {
                    const queue = [...(adjacency[graph.currentNodeId] ?? [])]
                    while (queue.length) {
                        const id = queue.pop() as string
                        if (id === graph.currentNodeId || directions[id]) {
                            continue
                        }
                        directions[id] = direction
                        queue.push(...(adjacency[id] ?? []))
                    }
                }
                walk(parents, 'upstream')
                walk(children, 'downstream')
                return directions
            },
        ],
        filteredLineage: [
            (s) => [s.lineageGraph, s.lineageDirections, s.lineageFilter],
            (
                graph: LineageGraphData | null,
                directions: Record<string, LineageDirection>,
                filter: LineageDirectionFilter
            ): LineageGraphData | null => {
                if (!graph || filter === 'all') {
                    return graph
                }
                const keep = new Set([
                    graph.currentNodeId,
                    ...Object.keys(directions).filter((id) => directions[id] === filter),
                ])
                return {
                    currentNodeId: graph.currentNodeId,
                    nodes: graph.nodes.filter((node) => keep.has(node.id)),
                    edges: graph.edges.filter((edge) => keep.has(edge.source_id) && keep.has(edge.target_id)),
                }
            },
        ],
        lineageRows: [
            (s) => [s.filteredLineage, s.lineageDirections],
            (graph: LineageGraphData | null, directions: Record<string, LineageDirection>): LineageRow[] => {
                if (!graph) {
                    return []
                }
                return graph.nodes
                    .filter((node) => node.id !== graph.currentNodeId && directions[node.id])
                    .map((node) => ({ node, direction: directions[node.id] }))
                    .sort(
                        (a, b) => a.direction.localeCompare(b.direction) * -1 || a.node.name.localeCompare(b.node.name)
                    )
            },
        ],
        hasMaterialization: [
            (s) => [s.node, s.savedQuery],
            (node: DataModelingNode | null, savedQuery: DataWarehouseSavedQuery | null): boolean =>
                (node?.type === 'matview' || node?.type === 'endpoint') && !!savedQuery?.is_materialized,
        ],
        effectiveLastRunAt: [
            (s) => [s.node, s.materializationJobs],
            (node: DataModelingNode | null, jobs: CountedPaginatedResponse<DataModelingJob> | null): string | null => {
                if (node?.last_run_at) {
                    return node.last_run_at
                }
                // Fall back to the most recent completed job
                const completedJob = jobs?.results?.find((j) => j.status === 'Completed')
                return completedJob?.last_run_at ?? null
            },
        ],
        effectiveLastRunStatus: [
            (s) => [s.node, s.materializationJobs],
            (node: DataModelingNode | null, jobs: CountedPaginatedResponse<DataModelingJob> | null): string | null =>
                node?.last_run_status || jobs?.results?.[0]?.status || null,
        ],
    }),
    listeners(({ actions, values }) => ({
        loadNodeSuccess: () => {
            const node = values.node
            if (node?.saved_query_id) {
                actions.loadSavedQuery()
            }
            actions.loadLineageGraph()
        },
        loadSavedQuerySuccess: () => {
            if (values.hasMaterialization) {
                actions.loadMaterializationJobs()
            }
        },
        setJobsOffset: () => {
            actions.loadMaterializationJobs()
        },
        updateDataWarehouseSavedQuerySuccess: () => {
            if (values.node?.saved_query_id) {
                actions.loadSavedQuery()
            }
        },
    })),
    actionToUrl(({ props, values }) => ({
        setTab: () => [
            urls.nodeDetail(props.id),
            { ...router.values.searchParams, tab: values.activeTab },
            router.values.hashParams,
        ],
    })),
    urlToAction(({ actions, values }) => ({
        [urls.nodeDetail(':id')]: (_, searchParams) => {
            const tab = searchParams.tab as NodeDetailTab | undefined
            if (tab && ['query', 'lineage', 'runs', 'quality'].includes(tab) && tab !== values.activeTab) {
                actions.setTab(tab)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadNode()
    }),
])
