export type duplicateDashboardLogicType = MakeLogicType<duplicateDashboardLogicValues, duplicateDashboardLogicActions>

export const duplicateDashboardLogic = kea<duplicateDashboardLogicType>([
    path(['scenes', 'dashboard', 'duplicateDashboardLogic']),
    connect(() => ({ actions: [insightsModel, ['insightsAddedToDashboard']] })),
    actions({
        showDuplicateDashboardModal: (id: number, name: string) => ({
            id,
            name,
        }),
        hideDuplicateDashboardModal: true,
        duplicateAndGoToDashboard: true,
    }),
    reducers({
        duplicateDashboardModalVisible: [
            false,
            {
                showDuplicateDashboardModal: () => true,
                hideDuplicateDashboardModal: () => false,
            },
        ],
        duplicateError: [
            null as string | null,
            {
                showDuplicateDashboardModal: () => null,
                hideDuplicateDashboardModal: () => null,
                submitDuplicateDashboardRequest: () => null,
                submitDuplicateDashboardFailure: (_, { error }: { error?: Error }) => error?.message ?? null,
            },
        ],
    }),
    forms(() => ({
        duplicateDashboard: {
            defaults: defaultFormValues,
            errors: () => ({}),
            submit: async ({ dashboardId, dashboardName, show, duplicateTiles }) => {
                if (!dashboardId) {
                    return
                }
                dashboardsModel.actions.duplicateDashboard({
                    id: dashboardId,
                    name: dashboardName,
                    show,
                    duplicateTiles,
                })
                // Wait for the create to settle so the button keeps its spinner and the modal
                // stays open until then. Throwing on failure lets kea-forms surface the error.
                const outcome = (await waitForCondition(
                    (action) =>
                        action.type === dashboardsModel.actionTypes.duplicateDashboardSuccess ||
                        action.type === dashboardsModel.actionTypes.duplicateDashboardFailure
                )) as { error?: string; errorObject?: { detail?: string } }
                // Only the failure action carries an error payload; success carries the dashboard.
                if (outcome.errorObject || outcome.error) {
                    throw new Error(
                        outcome.errorObject?.detail || outcome.error || 'Could not duplicate the dashboard. Try again.'
                    )
                }
            },
        },
    })),
    listeners(({ actions }) => ({
        hideDuplicateDashboardModal: () => {
            actions.resetDuplicateDashboard()
        },
        [dashboardsModel.actionTypes.duplicateDashboardSuccess]: ({
            dashboard,
            payload,
        }: {
            dashboard: DashboardType<QueryBasedInsightModel>
            payload?: Pick<DuplicateDashboardForm, 'duplicateTiles' | 'show'>
        }) => {
            actions.hideDuplicateDashboardModal()

            if (!payload?.duplicateTiles) {
                // any existing mounted insight will need to increment its dashboard count to update turbo mode
                const insightsOnDuplicatedDashboard = dashboard.tiles
                    .map((t) => t.insight?.id)
                    .filter((id): id is number => !!id)
                actions.insightsAddedToDashboard({
                    dashboardId: dashboard.id,
                    insightIds: insightsOnDuplicatedDashboard,
                })
            }

            if (payload?.show) {
                router.actions.push(urls.dashboard(dashboard.id))
            } else {
                if (router.values.currentLocation.pathname !== urls.dashboards()) {
                    router.actions.push(urls.dashboards())
                }
            }
        },
        duplicateAndGoToDashboard: () => {
            actions.setDuplicateDashboardValue('show', true)
            actions.submitDuplicateDashboard()
        },
        showDuplicateDashboardModal: ({ id, name }) => {
            actions.setDuplicateDashboardValues({ dashboardId: id, dashboardName: name })
        },
    })),
])
