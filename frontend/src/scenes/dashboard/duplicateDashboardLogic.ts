import { router } from 'kea-router'
import { waitForCondition } from 'kea-waitfor'

import { urls } from 'scenes/urls'

import { dashboardsModel } from '~/models/dashboardsModel'
import { insightsModel } from '~/models/insightsModel'

import type { DashboardType, QueryBasedInsightModel } from '../../types'

export interface DuplicateDashboardForm {
    dashboardId: number | null
    dashboardName?: string
    duplicateTiles: boolean
    show?: boolean
}

const defaultFormValues: DuplicateDashboardForm = {
    dashboardId: null,
    duplicateTiles: false,
    dashboardName: undefined,
    show: false,
}

