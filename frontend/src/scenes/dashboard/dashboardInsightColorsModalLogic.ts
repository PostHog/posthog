/** Throwaway switches so we can compare rendering options for the colors modal in one build.
 * Drop this, the action, the reducer, and every read of it once an option is chosen. */
export type ColorsModalPrototypeVariants = {
    /** Property section header: plain text vs the insight-editor breakdown pill. */
    propertyDisplay: 'text' | 'pill'
    /** Per-row color control: separate picker plus Auto/Reset vs one swatch that carries the state. */
    colorState: 'tag' | 'swatch'
    /** Help text: paragraph vs an info notice. */
    helpText: 'paragraph' | 'notice'
}

export const DEFAULT_COLORS_MODAL_PROTOTYPE_VARIANTS: ColorsModalPrototypeVariants = {
    propertyDisplay: 'pill',
    colorState: 'swatch',
    helpText: 'notice',
}

