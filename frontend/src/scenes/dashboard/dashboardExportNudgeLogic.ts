// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardExportNudgeLogicValues {
    exportNudgedDashboardIds: number[] // dashboardSubscribeNudgeStoreLogic
    suppressedDashboardIds: number[] // dashboardSubscribeNudgeStoreLogic
    featureFlags: FeatureFlagsSet // featureFlagLogic
    hasAvailableFeature: (feature: AvailableFeature, currentUsage?: number | undefined) => boolean // userLogic
    freeTierSubscriptionCount: number | null
    freeTierSubscriptionCountLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardExportNudgeLogicActions {
    markDashboardExportNudged: (dashboardId: number) => {
        dashboardId: number
    } // dashboardSubscribeNudgeStoreLogic
    suppressDashboardNudge: (dashboardId: number) => {
        dashboardId: number
    } // dashboardSubscribeNudgeStoreLogic
    loadFreeTierSubscriptionCount: (_?: unknown) => unknown
    loadFreeTierSubscriptionCountFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFreeTierSubscriptionCountSuccess: (
        freeTierSubscriptionCount: number,
        payload?: unknown
    ) => {
        freeTierSubscriptionCount: number
        payload?: unknown
    }
}

export type dashboardExportNudgeLogicType = MakeLogicType<
    dashboardExportNudgeLogicValues,
    dashboardExportNudgeLogicActions
>

// Shared state for the export nudge: persisted per-dashboard markers, entitlement, and the
// free-tier count (fetched at most once per session).
export const dashboardExportNudgeLogic = kea<dashboardExportNudgeLogicType>([
    path(['scenes', 'dashboard', 'dashboardExportNudgeLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            dashboardSubscribeNudgeStoreLogic({ scope: dashboardNudgeScopeKey() }),
            ['suppressedDashboardIds', 'exportNudgedDashboardIds'],
            userLogic,
            ['hasAvailableFeature'],
        ],
        actions: [
            dashboardSubscribeNudgeStoreLogic({ scope: dashboardNudgeScopeKey() }),
            ['suppressDashboardNudge', 'markDashboardExportNudged'],
        ],
    })),
    loaders(() => ({
        // The `load` prefix puts this on initKea's ERROR_FILTER_ALLOW_LIST, so a failed background
        // check doesn't toast at a user who never asked for anything.
        freeTierSubscriptionCount: [
            null as number | null,
            {
                loadFreeTierSubscriptionCount: async (_?: unknown, breakpoint?: BreakPointFunction) =>
                    await fetchTeamSubscriptionCount(breakpoint),
            },
        ],
    })),
    listeners(() => ({
        loadFreeTierSubscriptionCountFailure: ({ error, errorObject }) => {
            // A failed count check silently excludes a free-tier user (fail closed) — capture it so
            // the readout can tell that apart from genuinely being at the limit.
            captureExportNudgeCheckFailed('limit', {
                error_name: errorObject?.name,
                error_status: errorObject?.status,
                error_message: error,
            })
        },
    })),
])

/**
 * Every way the eligibility check can come back empty other than the user being ineligible, under
 * one event so the readout can tell the modes apart by `step`.
 */
export function captureExportNudgeCheckFailed(
    step: 'limit' | 'check' | 'timeout',
    properties: Record<string, unknown> = {}
): void {
    posthog.capture('dashboard export nudge check failed', { step, ...properties })
}

/** A dashboard whose exporter cleared every eligibility check except the experiment flag. */
export interface ExportNudgeCandidate {
    dashboardId: number
    dashboardName?: string | null
}

// Mounted on first use rather than from a caller's connect(), so exports outside dashboards don't
// pay for it. Left mounted afterwards so the free-tier count survives between exports.
function mountedExportNudgeLogic(): typeof dashboardExportNudgeLogic {
    if (!dashboardExportNudgeLogic.isMounted()) {
        dashboardExportNudgeLogic.mount()
    }
    return dashboardExportNudgeLogic
}

/**
 * Resolves the half of the check that needs the network, so an export can start it on kickoff and
 * read the answer once the export lands. Stops deliberately short of the experiment flag, which
 * `claimExportNudge` reads at the moment the nudge is rendered.
 */
export async function resolveExportNudgeEligibility(dashboardId: number): Promise<ExportNudgeCandidate | null> {
    const { values, actions, asyncActions } = mountedExportNudgeLogic()
    if (values.exportNudgedDashboardIds.includes(dashboardId) || values.suppressedDashboardIds.includes(dashboardId)) {
        return null
    }

    const hasSubscriptionsFeature = values.hasAvailableFeature(AvailableFeature.SUBSCRIPTIONS)
    if (!hasSubscriptionsFeature && values.freeTierSubscriptionCount === null) {
        await asyncActions.loadFreeTierSubscriptionCount()
    }
    if (!canNudgeToSubscribe(hasSubscriptionsFeature, values.freeTierSubscriptionCount)) {
        return null
    }

    const hasExistingSubscription = await fetchHasExistingSubscription(dashboardId)
    if (hasExistingSubscription === null) {
        return null // fail closed on a broken check
    }
    if (hasExistingSubscription) {
        // The exporter clearly knows the feature — stop nudging this dashboard from either
        // surface, even if the subscription is later deleted.
        actions.suppressDashboardNudge(dashboardId)
        return null
    }

    return { dashboardId, dashboardName: dashboardsModel.findMounted()?.values.rawDashboards[dashboardId]?.name }
}

/**
 * Last gate, run as the nudge is rendered so a nudge is never spent on a toast nobody saw.
 * Returns whether this exporter is in the treatment.
 */
export function claimExportNudge(dashboardId: number): boolean {
    const { values, actions } = mountedExportNudgeLogic()
    // Re-read rather than trust resolveExportNudgeEligibility's check: two exports of the same
    // dashboard both run that check before either of them gets here, so only this read sees a
    // claim the other one already made.
    if (values.exportNudgedDashboardIds.includes(dashboardId) || values.suppressedDashboardIds.includes(dashboardId)) {
        return false
    }
    // Reading featureFlags[...] fires the exposure event, so only read it once every other check
    // has passed.
    if (values.featureFlags[FEATURE_FLAGS.DASHBOARD_EXPORT_NUDGE] !== 'test') {
        return false
    }

    actions.markDashboardExportNudged(dashboardId)
    posthog.capture('dashboard export nudge shown', { dashboard_id: dashboardId })
    return true
}

/** Whether this dashboard already has a subscription. null means the check itself failed. */
async function fetchHasExistingSubscription(dashboardId: number): Promise<boolean | null> {
    try {
        return await fetchHasSubscriptionForDashboard(dashboardId)
    } catch (error: any) {
        captureExportNudgeCheckFailed('check', {
            dashboard_id: dashboardId,
            error_name: error?.name,
            error_status: error?.status,
            error_message: error?.message ?? String(error),
        })
        return null
    }
}
