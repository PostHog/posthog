import { FEATURE_FLAGS } from 'lib/constants'
import { dayjs, now } from 'lib/dayjs'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { eventUsageLogic } from 'lib/utils/eventUsageLogic'
import { userLogic } from 'scenes/userLogic'

import type { FeatureFlagsSet } from '../../lib/logic/featureFlagLogic'
import type { DashboardType, QueryBasedInsightModel, UserType } from '../../types'
import { teamLogic } from '../teamLogic'
import { dashboardLogic } from './dashboardLogic'

export interface DashboardOnboardingChecklistLogicProps {
    dashboardId: number
}

const storageKey = (teamId: number, userUuid: string, dashboardId: number): string =>
    `dashboard-onboarding-checklist.dismissed.${teamId}.${userUuid}.${dashboardId}`

