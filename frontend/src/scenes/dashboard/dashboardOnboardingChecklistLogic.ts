export interface dashboardOnboardingChecklistLogicValues {
    canEditDashboard: boolean // dashboardLogic
    dashboard: DashboardType<QueryBasedInsightModel> | null // dashboardLogic
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentTeamId: number | null // teamLogic
    user: UserType | null // userLogic
    active: boolean
    dismissed: boolean
    eligible: boolean
    storageKey: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dashboardOnboardingChecklistLogicActions {
    reportDashboardOnboardingChecklistDismissed: (dashboardId: number) => {
        dashboardId: number
    } // eventUsageLogic
    dismiss: () => {
        value: true
    }
    setDismissed: (dismissed: boolean) => {
        dismissed: boolean
    }
}

