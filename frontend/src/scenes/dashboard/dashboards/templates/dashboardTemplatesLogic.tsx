export const dashboardTemplatesLogic = kea<dashboardTemplatesLogicType>([
    path(['scenes', 'dashboard', 'dashboards', 'templates', 'dashboardTemplatesLogic']),
    props({} as DashboardTemplatesLogicProps),
    key(
        (p: DashboardTemplatesLogicProps) =>
            `${p.scope ?? 'default'}-${listQueryFeaturedKeySegment(p)}${p.templatesTabList ? '-templatesTab' : ''}`
    ),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], teamLogic, ['currentTeamId'], userLogic, ['user']],
    })),
    actions({
        setTemplates: (allTemplates: DashboardTemplateType[]) => ({ allTemplates }),
        setTemplateFilter: (search: string) => ({ search }),
        setTemplateNameOrdering: (ordering: DashboardTemplateTableOrdering) => ({ ordering }),
        setTemplatesTabVisibility: (visibility: DashboardTemplatesTabVisibility) => ({ visibility }),
        clearFilters: true,
    }),
    reducers({
        templateFilter: [
            '' as string,
            {
                setTemplateFilter: (_, { search }) => {
                    return search
                },
                clearFilters: () => '',
            },
        ],
        templateNameOrdering: [
            '' as DashboardTemplateTableOrdering,
            {
                setTemplateNameOrdering: (_, { ordering }) => ordering,
            },
        ],
        // lazyLoaders has no "loaded" flag; empty API results must not look "unfetched" forever (see urlToAction /dashboard).
        allTemplatesLoaded: [
            false,
            {
                getAllTemplatesSuccess: () => true,
            },
        ],
        // A failed request keeps the loader's last value, so a failed first load would look like an empty list.
        allTemplatesLoadFailed: [
            false,
            {
                getAllTemplates: () => false,
                getAllTemplatesSuccess: () => false,
                getAllTemplatesFailure: () => true,
            },
        ],
        templatesTabVisibility: [
            'all' as DashboardTemplatesTabVisibility,
            {
                setTemplatesTabVisibility: (_, { visibility }) => visibility,
                clearFilters: () => 'all',
            },
        ],
    }),
    selectors({
        /** Django `is_staff`, not the organization role. Until the user loads, read the bootstrap context so row actions are not blank. */
        isStaffViewer: [
            (s) => [s.user],
            (user: UserType | null): boolean =>
                user != null ? Boolean(user.is_staff) : Boolean(getAppContext()?.current_user?.is_staff),
        ],
        searchText: [
            (s) => [s.templateFilter],
            (templateFilter: string): string | null => (templateFilter.length >= 3 ? templateFilter : null),
        ],
        hasActiveFilters: [
            (s) => [s.searchText, s.templatesTabVisibility],
            (searchText: string | null, templatesTabVisibility: DashboardTemplatesTabVisibility): boolean =>
                searchText !== null || templatesTabVisibility !== 'all',
        ],
        // Org-scoped templates are readable org-wide but only their owning project may edit/delete/demote
        // them (see CustomerDashboardTemplateWritePermission). Team templates listed here are always owned.
        isManagedInAnotherProject: [
            (s) => [s.currentTeamId],
            (currentTeamId: number | null): ((template: DashboardTemplateType) => boolean) =>
                (template) =>
                    template.scope === 'organization' && template.team_id !== currentTeamId,
        ],
        canEditTemplates: [
            (s) => [s.isStaffViewer],
            (isStaffViewer: boolean): boolean =>
                // `dashboard_template` inherits `dashboard` in RBAC (#54694). The access level comes from the bootstrap
                // context, which changes only on a page load.
                isStaffViewer || userHasAccess(AccessControlResourceType.Dashboard, AccessControlLevel.Editor),
        ],
        canManageTemplate: [
            (s) => [s.isStaffViewer, s.canEditTemplates, s.isManagedInAnotherProject],
            (
                isStaffViewer: boolean,
                canEditTemplates: boolean,
                isManagedInAnotherProject: (template: DashboardTemplateType) => boolean
            ): ((template: DashboardTemplateType) => boolean) =>
                (template) =>
                    isStaffViewer ||
                    (canEditTemplates &&
                        (template.scope === 'team' || template.scope === 'organization') &&
                        !isManagedInAnotherProject(template)),
        ],
    }),
    lazyLoaders(({ props, values }) => ({
        allTemplates: [
            [] as DashboardTemplateType[],
            {
                getAllTemplates: async () => {
                    const logicProps = props as DashboardTemplatesLogicProps
                    const featuredOnly = logicProps.listQuery?.is_featured === true
                    // Curated featured list (empty dashboards) must ignore `templateFilter` synced from the URL via
                    // `urlToAction` when the templates modal or another surface leaves `?templateFilter=` on /dashboard.
                    const search = featuredOnly ? null : values.searchText
                    const useSearch = search !== null

                    let listScope: DashboardTemplateScope | undefined
                    if (logicProps.scope !== 'default' && logicProps.scope !== undefined) {
                        listScope = logicProps.scope
                    } else if (logicProps.templatesTabList) {
                        if (values.templatesTabVisibility === 'official') {
                            listScope = 'global'
                        } else if (values.templatesTabVisibility === 'project') {
                            listScope = 'team'
                        } else if (values.templatesTabVisibility === 'organization') {
                            listScope = 'organization'
                        } else {
                            listScope = undefined
                        }
                    } else {
                        listScope = undefined
                    }

                    const params: DashboardTemplateListParams = {
                        scope: listScope,
                        search: search ?? undefined,
                        // Search results are relevance-ranked; omit ordering (see API `dangerously_get_queryset`).
                        ordering: useSearch ? undefined : values.templateNameOrdering || undefined,
                        ...logicProps.listQuery,
                    }
                    // Customers can't manage PostHog's templates, so their "all" list is this project's plus the
                    // organization's. The API has no scope for that pair, so request both and merge. Staff keep the
                    // unscoped list.
                    if (logicProps.templatesTabList && listScope === undefined && !values.isStaffViewer) {
                        const [teamPage, organizationPage] = await Promise.all([
                            api.dashboardTemplates.list({ ...params, scope: 'team' }),
                            api.dashboardTemplates.list({ ...params, scope: 'organization' }),
                        ])
                        // A search ranks each page on the server, but the rank is not returned, so team matches come first.
                        const results = [...teamPage.results, ...organizationPage.results]
                        return useSearch
                            ? results
                            : sortTemplatesTeamScopeBeforeOfficial(results, values.templateNameOrdering)
                    }

                    const page = await api.dashboardTemplates.list(params)
                    if (!useSearch && listScope === undefined) {
                        return sortTemplatesTeamScopeBeforeOfficial(page.results, values.templateNameOrdering)
                    }
                    return page.results
                },
            },
        ],
    })),
    listeners(({ actions }) => ({
        setTemplateFilter: async (_, breakpoint) => {
            await breakpoint(400)
            actions.getAllTemplates()
        },
        setTemplateNameOrdering: () => {
            actions.getAllTemplates()
        },
        setTemplatesTabVisibility: () => {
            actions.getAllTemplates()
        },
        clearFilters: () => {
            actions.getAllTemplates()
        },
    })),
    urlToAction(({ actions, values }) => ({
        '/dashboard': (_, searchParams) => {
            const raw = searchParams.templateFilter
            const filter = Array.isArray(raw) ? raw[0] : raw
            const next = typeof filter === 'string' ? filter : ''
            // Same value as URL: skip setTemplateFilter — its listener debounces and would refetch (modal flicker).
            if (values.templateFilter !== next) {
                actions.setTemplateFilter(next)
            } else if (!values.allTemplatesLoading && !values.allTemplatesLoaded) {
                actions.getAllTemplates()
            }
        },
    })),
    actionToUrl(({ values }) => {
        const templateFilterToUrl = (): [
            string,
            Record<string, unknown>,
            Record<string, unknown>,
            { replace: boolean },
        ] => {
            const searchParams = { ...router.values.searchParams }
            searchParams.templateFilter = values.templateFilter
            if (!values.templateFilter) {
                delete searchParams.templateFilter
            }
            return ['/dashboard', searchParams, router.values.hashParams, { replace: true }]
        }
        return {
            setTemplateFilter: templateFilterToUrl,
            clearFilters: templateFilterToUrl,
        }
    }),
])
