export enum DashboardsTab {
    All = 'all',
    Yours = 'yours',
    Pinned = 'pinned',
    Templates = 'templates',
}

const DEFAULT_SORTING: Sorting = { columnKey: 'name', order: 1 }

export interface DashboardsFilters {
    search: string
    createdBy: number[] | 'All users'
    pinned: boolean
    shared: boolean
    tags?: string[]
    /** Folder path to filter to, e.g. 'Unfiled/Dashboards' (empty string = project root). null means no folder filter. */
    folder?: string | null
}

export const DEFAULT_FILTERS: DashboardsFilters = {
    search: '',
    createdBy: 'All users',
    pinned: false,
    shared: false,
    tags: [],
    folder: null,
}

export function hasDashboardFilters(filters: DashboardsFilters): boolean {
    return Boolean(
        filters.search ||
        filters.pinned ||
        filters.shared ||
        (filters.createdBy !== 'All users' && filters.createdBy.length > 0) ||
        filters.tags?.length ||
        filters.folder != null
    )
}

function moveTargetFor(dashboard: DashboardBasicType | undefined): FileSystemEntry | null {
    if (!dashboard?.file_system_id || !dashboard.file_system_path) {
        return null
    }
    return {
        id: dashboard.file_system_id,
        path: dashboard.file_system_path,
        type: 'dashboard',
        ref: String(dashboard.id),
        href: urls.dashboard(dashboard.id),
    }
}

/** Router may coerce numeric-looking query values to numbers; search text must stay a string. */
function urlSearchParamToString(value: unknown): string {
    return `${value ?? ''}`
}

