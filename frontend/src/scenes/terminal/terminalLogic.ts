export type terminalLogicType = MakeLogicType<terminalLogicValues, terminalLogicActions>

export const terminalLogic = kea<terminalLogicType>([
    path(['scenes', 'terminal', 'terminalLogic']),
    connect({
        values: [
            breadcrumbsLogic,
            ['projectTreeRef'],
            teamLogic,
            ['currentTeamId'],
            terminalDockLogic,
            ['terminalEnabled', 'dockOpen', 'requestedFolder'],
        ],
        actions: [terminalDockLogic, ['focusTerminal', 'setRequestedFolder']],
    }),
    actions({
        start: true,
        followFolder: true,
        attach: (container: HTMLElement) => ({ container }),
        detach: (container: HTMLElement) => ({ container }),
        focus: true,
        insertCommand: (command: string) => ({ command }),
        copy: true,
        paste: true,
        setHasSelection: (selected: boolean) => ({ selected }),
        setClipboardError: (error: string | null) => ({ error }),
        setPasting: (pasting: boolean) => ({ pasting }),
        stop: true,
        setStatus: (status: TerminalStatus) => ({ status }),
        setError: (error: string | null) => ({ error }),
        setSaveError: (error: string | null) => ({ error }),
    }),
    reducers({
        hasStarted: [false, { start: () => true }],
        runRequested: [false, { start: () => true, stop: () => false }],
        hasSelection: [false, { setHasSelection: (_, { selected }) => selected }],
        pasting: [false, { setPasting: (_, { pasting }) => pasting }],
        clipboardError: [null as string | null, { setClipboardError: (_, { error }) => error }],
        status: ['idle' as TerminalStatus, { setStatus: (_, { status }) => status, stop: () => 'idle' }],
        // Stop destroys the session, including the recovery copies a save error points at.
        error: [null as string | null, { setError: (_, { error }) => error, start: () => null, stop: () => null }],
        saveError: [
            null as string | null,
            { setSaveError: (_, { error }) => error, start: () => null, stop: () => null },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        followFolder: async (_, breakpoint) => {
            const runtime: TerminalRuntime | undefined = cache.runtime
            const filesystem: PosthogFilesystem | undefined = cache.filesystem
            if (!values.terminalEnabled || values.status !== 'ready' || !runtime || !filesystem) {
                return
            }
            const requested = values.requestedFolder
            try {
                const folder =
                    requested !== null
                        ? filesystem.folderPath(requested)
                        : await filesystem.folderFor(values.projectTreeRef)
                breakpoint()
                if (folder && cache.runtime === runtime) {
                    if (!runtime.changeDirectory(folder) && requested !== null) {
                        lemonToast.info(
                            'The terminal is busy. Finish the command or clear the prompt, then choose Open in terminal again.'
                        )
                    }
                }
            } catch (error) {
                if (error instanceof Error && isBreakpoint(error)) {
                    throw error
                }
                lemonToast.error('Could not find the terminal folder. Try Open in terminal from the Files menu.')
            } finally {
                if (values.requestedFolder === requested) {
                    actions.setRequestedFolder(null)
                }
            }
        },
        [terminalDockLogic.actionTypes.setDockOpen]: ({ open }) => {
            if (open) {
                actions.followFolder()
            }
        },
        attach: ({ container }) => {
            if (!cache.session) {
                cache.session = new TerminalSession(
                    (data) => cache.runtime?.write(data),
                    (columns, rows) => cache.runtime?.resize(columns, rows),
                    actions.setHasSelection,
                    actions.paste
                )
                cache.disposables.add(
                    () => () => {
                        cache.session.dispose()
                        cache.session = null
                    },
                    'screen',
                    { pauseOnPageHidden: false }
                )
            }
            cache.session.attach(container)
            if (!values.hasStarted) {
                actions.start()
            }
        },
        detach: ({ container }) => cache.session?.detach(container),
        focus: () => cache.session?.view.focus(),
        focusTerminal: () => actions.focus(),
        insertCommand: ({ command }) => {
            cache.session?.view.paste(command)
            actions.focus()
        },
        copy: () => void copyToClipboard(cache.session?.view.getSelection() ?? '', 'terminal selection'),
        paste: async () => {
            if (values.pasting) {
                return
            }
            actions.setPasting(true)
            actions.setClipboardError(null)
            try {
                const text = await navigator.clipboard.readText()
                cache.session?.view.paste(text)
                actions.focus()
            } catch {
                actions.setClipboardError(
                    'Could not read the clipboard. Focus the terminal and use your browser’s paste shortcut.'
                )
            } finally {
                actions.setPasting(false)
            }
        },
        [teamLogic.actionTypes.loadCurrentTeamSuccess]: ({ currentTeam }) => {
            if (cache.projectId === currentTeam?.id) {
                return
            }
            const restart = values.runRequested
            actions.stop()
            cache.filesystem = null
            cache.session?.view.clear()
            if (restart && cache.session) {
                actions.start()
            }
        },
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
            if (!values.terminalEnabled) {
                actions.stop()
            }
        },
        start: async () => {
            const projectId = values.currentTeamId
            if (!values.terminalEnabled || !projectId || ['loading', 'booting', 'ready'].includes(values.status)) {
                return
            }
            if (!cache.session) {
                return
            }
            cache.projectId = projectId
            const runtime = new TerminalRuntime((bytes) => cache.session?.view.write(bytes))
            cache.runtime = runtime
            cache.session.view.clear()
            runtime.resize(cache.session.view.cols, cache.session.view.rows)
            const controller = new AbortController()
            const disposables = cache.disposables
            disposables.add(
                () => () => {
                    controller.abort()
                    disposables.dispose('clock-sync')
                    runtime.dispose()
                    if (cache.runtime === runtime) {
                        cache.runtime = null
                        cache.filesystem = null
                    }
                    if (window.posthogTerminal?.read === agent.read) {
                        delete window.posthogTerminal
                    }
                },
                'terminal',
                { pauseOnPageHidden: false }
            )
            const agent: TerminalAgent = { write: (data) => runtime.write(data), read: () => runtime.read() }
            actions.setStatus('loading')
            try {
                const filesystem = new PosthogFilesystem(String(projectId), controller.signal)
                cache.filesystem = filesystem
                new PosthogCommands(String(projectId), controller.signal, filesystem, (url) => router.actions.push(url))
                actions.setStatus('booting')
                const server = new NinePServer(filesystem, (error) => {
                    if (!controller.signal.aborted) {
                        actions.setSaveError(error)
                    }
                })
                const requested = values.requestedFolder
                const projectTreeRef = values.projectTreeRef
                const folder =
                    requested !== null
                        ? filesystem.folderPath(requested)
                        : await filesystem.folderFor(projectTreeRef).catch(() => null)
                if (controller.signal.aborted) {
                    return
                }
                if (values.requestedFolder === requested) {
                    actions.setRequestedFolder(null)
                }
                await runtime.start(
                    server,
                    controller.signal,
                    () => {
                        if (!controller.signal.aborted) {
                            window.posthogTerminal = agent
                            actions.setStatus('ready')
                            if (
                                values.requestedFolder !== null ||
                                (values.dockOpen &&
                                    (values.projectTreeRef?.type !== projectTreeRef?.type ||
                                        values.projectTreeRef?.ref !== projectTreeRef?.ref))
                            ) {
                                actions.followFolder()
                            }
                            disposables.add(() => {
                                runtime.syncClock()
                                const interval = setInterval(() => runtime.syncClock(), 30_000)
                                return () => clearInterval(interval)
                            }, 'clock-sync')
                        }
                    },
                    folder ?? undefined
                )
                if (controller.signal.aborted) {
                    return
                }
                disposables.add(
                    () => {
                        const timeout = setTimeout(() => {
                            if (!controller.signal.aborted && values.status === 'booting') {
                                actions.setError('Linux did not finish starting. Stop the terminal and try again.')
                                actions.setStatus('error')
                                disposables.dispose('terminal')
                            }
                        }, 90_000)
                        return () => clearTimeout(timeout)
                    },
                    'boot-timeout',
                    { pauseOnPageHidden: false }
                )
            } catch (error) {
                if (!controller.signal.aborted) {
                    actions.setError(
                        error instanceof Error ? error.message : 'Could not start the terminal. Try again.'
                    )
                    actions.setStatus('error')
                    disposables.dispose('terminal')
                }
            }
        },
        stop: () => {
            cache.disposables.dispose('terminal')
            cache.disposables.dispose('boot-timeout')
        },
    })),
    subscriptions(({ actions, values }) => ({
        // Each scene derives this reference from its own state, so no single navigation action covers it.
        projectTreeRef: () => {
            if (values.dockOpen) {
                actions.followFolder()
            }
        },
    })),
])
