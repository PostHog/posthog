import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { teamLogic } from 'scenes/teamLogic'

import { NinePServer } from './ninepServer'
import { PosthogCommands } from './posthogCommands'
import { PosthogFilesystem } from './posthogFilesystem'
import { TerminalRuntime } from './terminalRuntime'

export interface TerminalAgent {
    write: (data: string) => void
    read: () => string
}

declare global {
    interface Window {
        posthogTerminal?: TerminalAgent
    }
}

export type TerminalStatus = 'idle' | 'loading' | 'booting' | 'ready' | 'error'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface terminalLogicValues {
    currentTeamId: number | null // teamLogic
    error: string | null
    saveError: string | null
    status: TerminalStatus
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface terminalLogicActions {
    setError: (error: string | null) => {
        error: string | null
    }
    setSaveError: (error: string | null) => {
        error: string | null
    }
    setStatus: (status: TerminalStatus) => {
        status: TerminalStatus
    }
    start: (runtime: TerminalRuntime) => {
        runtime: TerminalRuntime
    }
    stop: () => {
        value: true
    }
}

export type terminalLogicType = MakeLogicType<terminalLogicValues, terminalLogicActions>

export const terminalLogic = kea<terminalLogicType>([
    path(['scenes', 'terminal', 'terminalLogic']),
    connect({ values: [teamLogic, ['currentTeamId']] }),
    actions({
        start: (runtime: TerminalRuntime) => ({ runtime }),
        stop: true,
        setStatus: (status: TerminalStatus) => ({ status }),
        setError: (error: string | null) => ({ error }),
        setSaveError: (error: string | null) => ({ error }),
    }),
    reducers({
        status: ['idle' as TerminalStatus, { setStatus: (_, { status }) => status, stop: () => 'idle' }],
        error: [null as string | null, { setError: (_, { error }) => error, start: () => null }],
        saveError: [null as string | null, { setSaveError: (_, { error }) => error, start: () => null }],
    }),
    listeners(({ actions, values, cache }) => ({
        start: async ({ runtime }, breakpoint) => {
            const projectId = values.currentTeamId
            if (!projectId || ['loading', 'booting', 'ready'].includes(values.status)) {
                runtime.dispose()
                return
            }
            const controller = new AbortController()
            const disposables = cache.disposables
            disposables.add(
                () => () => {
                    controller.abort()
                    runtime.dispose()
                    if (window.posthogTerminal?.read === agent.read) {
                        delete window.posthogTerminal
                    }
                },
                'terminal',
                { pauseOnPageHidden: false }
            )
            const agent: TerminalAgent = { write: (data) => runtime.write(data), read: () => runtime.read() }
            actions.setStatus('loading')
            try {
                const filesystem = new PosthogFilesystem(String(projectId), controller.signal)
                await filesystem.load()
                new PosthogCommands(String(projectId), controller.signal, filesystem)
                breakpoint()
                if (controller.signal.aborted) {
                    return
                }
                actions.setStatus('booting')
                const server = new NinePServer(filesystem, (error) => {
                    if (!controller.signal.aborted) {
                        actions.setSaveError(error)
                    }
                })
                await runtime.start(server, controller.signal, () => {
                    if (!controller.signal.aborted) {
                        window.posthogTerminal = agent
                        actions.setStatus('ready')
                    }
                })
                disposables.add(
                    () => {
                        const timeout = setTimeout(() => {
                            if (!controller.signal.aborted && values.status === 'booting') {
                                actions.setError('Linux did not finish starting. Stop the terminal and try again.')
                                actions.setStatus('error')
                                disposables.dispose('terminal')
                            }
                        }, 90_000)
                        return () => clearTimeout(timeout)
                    },
                    'boot-timeout',
                    { pauseOnPageHidden: false }
                )
            } catch (error) {
                if (!controller.signal.aborted) {
                    actions.setError(
                        error instanceof Error ? error.message : 'Could not start the terminal. Try again.'
                    )
                    actions.setStatus('error')
                    disposables.dispose('terminal')
                }
            }
        },
        stop: () => {
            cache.disposables.dispose('terminal')
            cache.disposables.dispose('boot-timeout')
        },
    })),
])
