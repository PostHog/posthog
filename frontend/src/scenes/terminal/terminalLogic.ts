export interface TerminalAgent {
    write: (data: string) => void
    read: () => string
}

declare global {
    interface Window {
        posthogTerminal?: TerminalAgent
    }
}

export type TerminalEnvironment = 'posthog-linux-wasm' | 'modal'
export type TerminalStatus = 'idle' | 'loading' | 'booting' | 'ready' | 'stopping' | 'error'

