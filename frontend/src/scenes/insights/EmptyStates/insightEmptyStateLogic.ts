/** Works out why an insight came back empty, from when each of its events was last sent. */
export const insightEmptyStateLogic = kea<insightEmptyStateLogicType>([
    props({} as InsightEmptyStateLogicProps),
    key(({ insightProps }) => keyForInsightLogicProps('new')(insightProps)),
    path((key) => ['scenes', 'insights', 'EmptyStates', 'insightEmptyStateLogic', key]),
    connect(({ insightProps }: InsightEmptyStateLogicProps) => ({
        values: [
            insightVizDataLogic(insightProps),
            ['querySource', 'dateRange', 'insightData'],
            teamLogic,
            ['currentTeamId'],
        ],
    })),
    loaders(({ values }) => ({
        lastSeen: [
            null as Record<string, string | null> | null,
            {
                loadLastSeen: async (events: string[], breakpoint) => {
                    const response = await eventDefinitionsList(String(values.currentTeamId), {
                        names: events,
                        limit: events.length,
                    })
                    breakpoint()
                    const lastSeen: Record<string, string | null> = Object.fromEntries(
                        events.map((event) => [event, null])
                    )
                    for (const definition of response.results) {
                        lastSeen[definition.name] = definition.last_seen_at ?? null
                    }
                    return lastSeen
                },
            },
        ],
    })),
    selectors({
        // Only plain event series can be looked up. Actions, data warehouse tables and "All events" stay unexplained.
        seriesEvents: [
            (s) => [s.querySource],
            (
                querySource:
                    | FunnelsQuery
                    | LifecycleQuery
                    | PathsQuery
                    | PathsV2Query
                    | RetentionQuery
                    | StickinessQuery
                    | TrendsQuery
                    | WebOverviewQuery
                    | WebStatsTableQuery
                    | null
            ): string[] | null => explainableEvents(querySource),
        ],
        hasInsightFilters: [
            (s) => [s.querySource],
            (
                querySource:
                    | FunnelsQuery
                    | LifecycleQuery
                    | PathsQuery
                    | PathsV2Query
                    | RetentionQuery
                    | StickinessQuery
                    | TrendsQuery
                    | WebOverviewQuery
                    | WebStatsTableQuery
                    | null
            ): boolean =>
                !!querySource && (hasPropertyFilters(querySource.properties) || !!querySource.filterTestAccounts),
        ],
        hasSeriesFilters: [
            (s) => [s.querySource],
            (
                querySource:
                    | FunnelsQuery
                    | LifecycleQuery
                    | PathsQuery
                    | PathsV2Query
                    | RetentionQuery
                    | StickinessQuery
                    | TrendsQuery
                    | WebOverviewQuery
                    | WebStatsTableQuery
                    | null
            ): boolean =>
                !!querySource &&
                'series' in querySource &&
                querySource.series.some((node) => hasPropertyFilters(node.properties)),
        ],
        reason: [
            (s) => [
                s.seriesEvents,
                s.lastSeen,
                s.lastSeenLoading,
                s.insightData,
                s.dateRange,
                s.hasInsightFilters,
                s.hasSeriesFilters,
            ],
            (
                seriesEvents: string[] | null,
                lastSeen: Record<string, string | null> | null,
                lastSeenLoading: boolean,
                insightData: Record<string, any>,
                dateRange: DateRange | null | undefined,
                hasInsightFilters: boolean,
                hasSeriesFilters: boolean
            ): EmptyStateReason =>
                // lastSeen can still hold the previous series' events after the query changes.
                !seriesEvents || !lastSeen || lastSeenLoading || !objectsEqual(Object.keys(lastSeen), seriesEvents)
                    ? { kind: 'unknown' }
                    : emptyStateReason({
                          lastSeen,
                          ...emptyStateRange(insightData?.resolved_date_range, dateRange),
                          hasFilters: hasInsightFilters || hasSeriesFilters,
                      }),
        ],
    }),
    subscriptions(({ actions }) => ({
        seriesEvents: (events: string[] | null, previous: string[] | null) => {
            if (events && !objectsEqual(events, previous)) {
                actions.loadLastSeen(events)
            }
        },
    })),
])
