import { MakeLogicType, actions, connect, kea, key, listeners, path, props, selectors } from 'kea'

import { keyForInsightLogicProps } from 'scenes/insights/sharedUtils'
import { teamLogic } from 'scenes/teamLogic'

import { HogQLQueryModifiers } from '~/queries/schema/schema-general'
import { InsightLogicProps, TeamPublicType, TeamType } from '~/types'

import type {
    FunnelsQuery,
    LifecycleQuery,
    PathsQuery,
    RetentionQuery,
    StickinessQuery,
    TrendsQuery,
    WebOverviewQuery,
    WebStatsTableQuery,
} from '../../../queries/schema/schema-general'
import type { PathsV2Query } from '../../../queries/schema/schema-general'
import { insightVizDataLogic } from '../insightVizDataLogic'
import type { QuerySourceUpdate } from '../insightVizDataLogic'

export type PoeModeTypes = HogQLQueryModifiers['personsOnEventsMode'] | null

const QUERY_TIME_POE_MODE = 'person_id_override_properties_joined'
const EVENT_TIME_POE_MODE = 'person_id_override_properties_on_events'

// `disabled` is a deprecated alias of QUERY_TIME_POE_MODE, so it reads as query time too.
const QUERY_TIME_POE_MODES: PoeModeTypes[] = [QUERY_TIME_POE_MODE, 'disabled']

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface poeFilterLogicValues {
    querySource:
        | FunnelsQuery
        | LifecycleQuery
        | PathsQuery
        | PathsV2Query
        | RetentionQuery
        | StickinessQuery
        | TrendsQuery
        | WebOverviewQuery
        | WebStatsTableQuery
        | null // insightVizDataLogic
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    projectPoeMode: PoeModeTypes
    queryTimePoeEnabled: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface poeFilterLogicActions {
    updateQuerySource: (querySource: QuerySourceUpdate) => {
        querySource: QuerySourceUpdate
    } // insightVizDataLogic
    setQueryTimePoeEnabled: (enabled: boolean) => {
        enabled: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface poeFilterLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        projectPoeMode: (currentTeam: TeamPublicType | TeamType | null) => PoeModeTypes
        queryTimePoeEnabled: (
            querySource:
                | FunnelsQuery
                | LifecycleQuery
                | PathsQuery
                | PathsV2Query
                | RetentionQuery
                | StickinessQuery
                | TrendsQuery
                | WebOverviewQuery
                | WebStatsTableQuery
                | null,
            projectPoeMode: PoeModeTypes
        ) => boolean
    }
}

export type poeFilterLogicType = MakeLogicType<
    poeFilterLogicValues,
    poeFilterLogicActions,
    InsightLogicProps,
    poeFilterLogicMeta
>

export const poeFilterLogic = kea<poeFilterLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['scenes', 'insights', 'EditorFilters', 'poeFilterLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [insightVizDataLogic(props), ['querySource'], teamLogic, ['currentTeam']],
        actions: [insightVizDataLogic(props), ['updateQuerySource']],
    })),
    actions(() => ({
        setQueryTimePoeEnabled: (enabled: boolean) => ({ enabled }),
    })),
    selectors({
        // Mirrors the backend: the project override wins over the flag-based default.
        projectPoeMode: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | TeamPublicType | null): PoeModeTypes =>
                currentTeam?.modifiers?.personsOnEventsMode ??
                currentTeam?.default_modifiers?.personsOnEventsMode ??
                null,
        ],
        queryTimePoeEnabled: [
            (s) => [s.querySource, s.projectPoeMode],
            (
                querySource:
                    | FunnelsQuery
                    | LifecycleQuery
                    | PathsQuery
                    | PathsV2Query
                    | RetentionQuery
                    | StickinessQuery
                    | TrendsQuery
                    | WebOverviewQuery
                    | WebStatsTableQuery
                    | null,
                projectPoeMode: PoeModeTypes
            ): boolean => QUERY_TIME_POE_MODES.includes(querySource?.modifiers?.personsOnEventsMode ?? projectPoeMode),
        ],
    }),
    listeners(({ actions, values }) => ({
        setQueryTimePoeEnabled: ({ enabled }) => {
            let personsOnEventsMode: HogQLQueryModifiers['personsOnEventsMode']
            if (enabled) {
                personsOnEventsMode = QUERY_TIME_POE_MODE
            } else if (QUERY_TIME_POE_MODES.includes(values.projectPoeMode)) {
                // Clearing the modifier falls back to the project default, which is also query
                // time. The insight must name event time itself.
                personsOnEventsMode = EVENT_TIME_POE_MODE
            }
            actions.updateQuerySource({
                modifiers: { ...values.querySource?.modifiers, personsOnEventsMode },
            })
        },
    })),
])
