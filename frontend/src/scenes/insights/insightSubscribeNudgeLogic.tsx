export const insightSubscribeNudgeLogic = kea<insightSubscribeNudgeLogicType>([
    path((key) => ['scenes', 'insights', 'insightSubscribeNudgeLogic', key]),
    props({} as InsightSubscribeNudgeLogicProps),
    key((props) => props.insightId),
    connect((props: InsightSubscribeNudgeLogicProps) => ({
        values: [
            userLogic,
            ['hasAvailableFeature'],
            insightSubscribeNudgeStoreLogic({ scope: insightNudgeScopeKey() }),
            ['viewLog', 'suppressedInsightIds', 'notifiedInsightIds'],
        ],
        actions: [
            insightUsageLogic(props.insightProps),
            ['reportInsightViewed'],
            insightSubscribeNudgeStoreLogic({ scope: insightNudgeScopeKey() }),
            ['recordInsightView', 'suppressInsightNudge', 'markInsightNotified'],
        ],
    })),
    loaders(({ props }) => ({
        hasExistingSubscription: [
            null as boolean | null,
            {
                loadExistingSubscription: async (_?: unknown, breakpoint?: BreakPointFunction) =>
                    await fetchHasSubscriptionForInsightId(props.insightId, breakpoint),
            },
        ],
        freeTierSubscriptionCount: [
            null as number | null,
            {
                loadFreeTierSubscriptionCount: async (_?: unknown, breakpoint?: BreakPointFunction) =>
                    await fetchTeamSubscriptionCount(breakpoint),
            },
        ],
    })),
    selectors({
        viewCount7d: [
            (s) => [s.viewLog, (_, props) => props.insightId],
            (viewLog: InsightViewLog, insightId): number =>
                freshInsightViewTimestamps(viewLog[insightId] ?? [], Date.now()).length,
        ],
        isCandidate: [
            (s) => [
                s.viewCount7d,
                s.suppressedInsightIds,
                s.notifiedInsightIds,
                (_, props) => props.insightId,
                (_, props) => props.canEditInsight,
            ],
            (count: number, suppressed: number[], notified: number[], insightId, canEdit) =>
                count >= INSIGHT_SUBSCRIBE_NUDGE_VIEW_THRESHOLD &&
                canEdit &&
                !suppressed.includes(insightId) &&
                !notified.includes(insightId),
        ],
        showNudge: [
            (s) => [s.isCandidate, s.hasExistingSubscription, s.hasAvailableFeature, s.freeTierSubscriptionCount],
            (
                candidate: boolean,
                hasSubscription: boolean | null,
                hasFeature: (feature: AvailableFeature, currentUsage?: number | undefined) => boolean, // userLogic
                count: number | null
            ) =>
                candidate &&
                hasSubscription === false &&
                canNudgeToSubscribe(hasFeature(AvailableFeature.SUBSCRIPTIONS), count),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        reportInsightViewed: () => actions.recordInsightView(props.insightId),
        recordInsightView: ({ insightId }) => {
            if (
                insightId === props.insightId &&
                values.isCandidate &&
                values.hasExistingSubscription === null &&
                !values.hasExistingSubscriptionLoading
            ) {
                actions.loadExistingSubscription()
            }
            if (
                insightId === props.insightId &&
                values.isCandidate &&
                !values.hasAvailableFeature(AvailableFeature.SUBSCRIPTIONS) &&
                values.freeTierSubscriptionCount === null &&
                !values.freeTierSubscriptionCountLoading
            ) {
                actions.loadFreeTierSubscriptionCount()
            }
        },
        loadExistingSubscriptionSuccess: ({ hasExistingSubscription }) => {
            if (hasExistingSubscription) {
                actions.suppressInsightNudge(props.insightId)
            }
        },
    })),
    subscriptions(({ actions, values, cache, props }) => ({
        showNudge: (showNudge: boolean) => {
            if (showNudge && !cache.nudgeShown) {
                cache.nudgeShown = true
                actions.markInsightNotified(props.insightId)
                posthog.capture('insight subscribe nudge shown', {
                    insight_id: props.insightId,
                    view_count_7d: values.viewCount7d,
                })
                showInsightSubscribeNudgeToast(
                    props.insightId,
                    props.insightShortId,
                    props.insightName,
                    values.viewCount7d
                )
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.isCandidate) {
            actions.loadExistingSubscription()
            if (!values.hasAvailableFeature(AvailableFeature.SUBSCRIPTIONS)) {
                actions.loadFreeTierSubscriptionCount()
            }
        }
    }),
])
