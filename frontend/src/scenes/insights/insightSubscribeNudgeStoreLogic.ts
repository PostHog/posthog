import { MakeLogicType, actions, kea, key, path, props, reducers } from 'kea'

import { getCurrentTeamIdOrNone, getCurrentUserIdOrNone } from 'lib/utils/getAppContext'

export const INSIGHT_VIEW_LOG_WINDOW_MS = 7 * 24 * 60 * 60 * 1000
export const INSIGHT_VIEW_DEDUPE_WINDOW_MS = 60 * 1000
export const MAX_TRACKED_INSIGHTS = 100

export type InsightViewLog = Record<string, number[]>

export function freshInsightViewTimestamps(timestamps: number[], now: number): number[] {
    return timestamps.filter((timestamp) => timestamp > now - INSIGHT_VIEW_LOG_WINDOW_MS)
}

export function insightNudgeScopeKey(): string {
    return `${getCurrentTeamIdOrNone() ?? 'anon'}:${getCurrentUserIdOrNone() ?? 'anon'}`
}

export interface InsightSubscribeNudgeStoreLogicProps {
    scope: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightSubscribeNudgeStoreLogicValues {
    notifiedInsightIds: number[]
    suppressedInsightIds: number[]
    viewLog: InsightViewLog
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightSubscribeNudgeStoreLogicActions {
    markInsightNotified: (insightId: number) => {
        insightId: number
    }
    recordInsightView: (insightId: number) => {
        insightId: number
    }
    suppressInsightNudge: (insightId: number) => {
        insightId: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightSubscribeNudgeStoreLogicMeta {
    key: string
}

export type insightSubscribeNudgeStoreLogicType = MakeLogicType<
    insightSubscribeNudgeStoreLogicValues,
    insightSubscribeNudgeStoreLogicActions,
    InsightSubscribeNudgeStoreLogicProps,
    insightSubscribeNudgeStoreLogicMeta
>

export const insightSubscribeNudgeStoreLogic = kea<insightSubscribeNudgeStoreLogicType>([
    path((key) => ['scenes', 'insights', 'insightSubscribeNudgeStoreLogic', key]),
    props({} as InsightSubscribeNudgeStoreLogicProps),
    key((props) => props.scope),
    actions({
        recordInsightView: (insightId: number) => ({ insightId }),
        suppressInsightNudge: (insightId: number) => ({ insightId }),
        markInsightNotified: (insightId: number) => ({ insightId }),
    }),
    reducers({
        viewLog: [
            {} as InsightViewLog,
            { persist: true },
            {
                recordInsightView: (state, { insightId }) => {
                    const now = Date.now()
                    const next: InsightViewLog = {}
                    for (const [id, timestamps] of Object.entries(state)) {
                        const fresh = freshInsightViewTimestamps(timestamps, now)
                        if (fresh.length) {
                            next[id] = fresh
                        }
                    }
                    const existing = next[insightId] ?? []
                    if (existing.length && now - existing[existing.length - 1] < INSIGHT_VIEW_DEDUPE_WINDOW_MS) {
                        return next
                    }
                    next[insightId] = [...existing, now]
                    const ids = Object.keys(next)
                    if (ids.length > MAX_TRACKED_INSIGHTS) {
                        ids.sort((a, b) => next[a][next[a].length - 1] - next[b][next[b].length - 1])
                        for (const id of ids.slice(0, ids.length - MAX_TRACKED_INSIGHTS)) {
                            delete next[id]
                        }
                    }
                    return next
                },
            },
        ],
        suppressedInsightIds: [
            [] as number[],
            { persist: true },
            {
                suppressInsightNudge: (state, { insightId }) =>
                    state.includes(insightId) ? state : [...state, insightId],
            },
        ],
        notifiedInsightIds: [
            [] as number[],
            { persist: true },
            {
                markInsightNotified: (state, { insightId }) =>
                    state.includes(insightId) ? state : [...state, insightId],
            },
        ],
    }),
])
