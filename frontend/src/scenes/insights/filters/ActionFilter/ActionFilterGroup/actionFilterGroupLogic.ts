/** Extract math properties from a node for spreading */
function getMathProps(node: SeriesNode): Record<string, any> {
    return {
        ...(node.math && { math: node.math }),
        ...(node.math_property && { math_property: node.math_property }),
        ...(node.math_property_type && { math_property_type: node.math_property_type }),
        ...(node.math_hogql && { math_hogql: node.math_hogql }),
        ...(node.math_group_type_index !== undefined && {
            math_group_type_index: node.math_group_type_index,
        }),
    }
}

