export const actionFilterGroupLogic = kea<actionFilterGroupLogicType>([
    path(['scenes', 'insights', 'filters', 'ActionFilter', 'ActionFilterGroup', 'actionFilterGroupLogic']),
    props({} as ActionFilterGroupLogicProps),
    key((props) => props.filterUuid),
    connect((props: ActionFilterGroupLogicProps) => ({
        actions: [entityFilterLogic({ typeKey: props.typeKey }), ['updateSeriesEntity as updateParentSeries']],
        values: [entityFilterLogic({ typeKey: props.typeKey }), ['localSeries'], mathsLogic, ['mathDefinitions']],
    })),

    actions({
        addNestedSeries: (key: string, name: string, kind: SeriesNode['kind']) => ({ key, name, kind }),
        updateNestedSeries: (nestedIndex: number, updates: Partial<AnyEntityNode>) => ({ nestedIndex, updates }),
        updateNestedSeriesProperties: (nestedIndex: number, properties: AnyPropertyFilter[]) => ({
            nestedIndex,
            properties,
        }),
        removeNestedSeries: (nestedIndex: number) => ({ nestedIndex }),
        setMath: (selectedMath: string | undefined, defaultMathHogQLExpression: string) => ({
            selectedMath,
            defaultMathHogQLExpression,
        }),
        setMathProperty: (property: string, propertyType: TaxonomicFilterGroupType) => ({ property, propertyType }),
        setMathHogQL: (hogql: string) => ({ hogql }),
        setHogQLDropdownVisible: (visible: boolean) => ({ visible }),
    }),

    reducers({
        isHogQLDropdownVisible: [
            false,
            {
                setHogQLDropdownVisible: (_, { visible }) => visible,
            },
        ],
    }),

    selectors({
        groupNode: [
            (s, p) => [s.localSeries, p.groupIndex],
            (localSeries: LocalSeries[], groupIndex: number): GroupNode | undefined => {
                const node = localSeries[groupIndex]?.node
                return isGroupSeriesNode(node) ? node : undefined
            },
        ],
        nestedNodes: [
            (s) => [s.groupNode],
            (groupNode: GroupNode | undefined): AnyEntityNode[] => groupNode?.nodes ?? [],
        ],
        operator: [
            (s) => [s.groupNode],
            (groupNode: GroupNode | undefined): FilterLogicalOperator =>
                groupNode?.operator || FilterLogicalOperator.Or,
        ],
    }),

    listeners(({ actions, values, props }) => {
        const updateGroup = (nestedNodes: AnyEntityNode[], extras: Record<string, any> = {}): void => {
            const groupNode = values.groupNode
            if (!groupNode) {
                return
            }

            actions.updateParentSeries(props.groupIndex, {
                kind: NodeKind.GroupNode,
                operator: values.operator,
                nodes: nestedNodes,
                name: nestedNodes.map((v) => v.name).join(', '),
                ...(groupNode.custom_name !== undefined && { custom_name: groupNode.custom_name }),
                ...getMathProps(groupNode),
                ...extras,
            })
        }

        return {
            addNestedSeries: ({ key, name, kind }) => {
                const groupNode = values.groupNode
                if (!groupNode) {
                    return
                }

                const newNode = withLatestVersion({
                    kind,
                    ...(kind === NodeKind.ActionsNode ? { id: parseInt(key) } : { event: key }),
                    name,
                    ...getMathProps(groupNode),
                } as SeriesNode) as AnyEntityNode

                updateGroup([...values.nestedNodes, newNode])
            },
            updateNestedSeries: ({ nestedIndex, updates }) => {
                const newNodes = [...values.nestedNodes]
                newNodes[nestedIndex] = { ...newNodes[nestedIndex], ...updates } as AnyEntityNode
                updateGroup(newNodes)
            },
            updateNestedSeriesProperties: ({ nestedIndex, properties }) => {
                const newNodes = [...values.nestedNodes]
                newNodes[nestedIndex] = { ...newNodes[nestedIndex], properties } as AnyEntityNode
                updateGroup(newNodes)
            },
            removeNestedSeries: ({ nestedIndex }) => {
                updateGroup(values.nestedNodes.filter((_, i) => i !== nestedIndex))
            },
            setMath: ({ selectedMath, defaultMathHogQLExpression }) => {
                const groupNode = values.groupNode
                if (!groupNode) {
                    return
                }

                let mathProps: Record<string, any>
                if (selectedMath) {
                    const mathDef = values.mathDefinitions[selectedMath]
                    const apiValues = mathTypeToApiValues(selectedMath)
                    mathProps = {
                        ...apiValues,
                        ...(apiValues.math_group_type_index === undefined && { math_group_type_index: undefined }),
                        math_property:
                            mathDef?.category === MathCategory.PropertyValue
                                ? (groupNode.math_property ?? '$time')
                                : undefined,
                        math_hogql:
                            mathDef?.category === MathCategory.HogQLExpression
                                ? (groupNode.math_hogql ?? defaultMathHogQLExpression)
                                : undefined,
                        math_property_type: groupNode.math_property_type,
                    }
                } else {
                    mathProps = {
                        math: undefined,
                        math_property: undefined,
                        math_property_type: undefined,
                        math_hogql: undefined,
                        math_group_type_index: undefined,
                    }
                }

                const newNodes = values.nestedNodes.map((f) => ({ ...f, ...mathProps }) as AnyEntityNode)
                updateGroup(newNodes, mathProps)
            },
            setMathProperty: ({ property, propertyType }) => {
                const groupNode = values.groupNode
                if (!groupNode) {
                    return
                }

                const mathProps = {
                    math_property: property,
                    math_property_type: propertyType,
                    math_hogql: undefined,
                }
                const newNodes = values.nestedNodes.map((f) => ({ ...f, ...mathProps }) as AnyEntityNode)
                updateGroup(newNodes, { math: groupNode.math, ...mathProps })
            },
            setMathHogQL: ({ hogql }) => {
                const groupNode = values.groupNode
                if (!groupNode) {
                    return
                }

                const mathProps = {
                    math_property: undefined,
                    math_property_type: undefined,
                    math_hogql: hogql,
                }
                const newNodes = values.nestedNodes.map((f) => ({ ...f, ...mathProps }) as AnyEntityNode)
                updateGroup(newNodes, { math: groupNode.math, ...mathProps })
            },
        }
    }),
])
