const IS_TEST_MODE = process.env.NODE_ENV === 'test'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightUsageLogicValues {
    query: DataNode<Record<string, any>>; // dataNodeLogic
    insight: Partial<QueryBasedInsightModel<Node<Record<string, any>>>>; // insightLogic
    currentProjectId: number | null; // projectLogic
    hasAvailableFeature: (feature: AvailableFeature, currentUsage?: number | undefined) => boolean; // userLogic
    isFirstLoad: boolean;
    nudgeRequested: boolean;
    nudgeViewTimestamps: number[];
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightUsageLogicActions {
    reportInsightViewed: (insightModel: Partial<QueryBasedInsightModel<Node<Record<string, any>>>>, query: Node<Record<string, any>> | null, isFirstLoad: boolean, delay?: number | undefined) => {
        delay: number | undefined;
        insightModel: Partial<QueryBasedInsightModel<Node<Record<string, any>>>>;
        isFirstLoad: boolean;
        query: Node<Record<string, any>> | null;
    }; // eventUsageLogic
    onQueryChange: (query: Node | null, previousQuery?: Node | null) => {
        previousQuery: Node<Record<string, any>> | null | undefined;
        query: Node<Record<string, any>> | null;
    };
    recordNudgeView: () => {
        value: true;
    };
    requestInsightSubscriptionNudge: () => {
        value: true;
    };
    setNotFirstLoad: () => {
        value: true;
    };
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightUsageLogicMeta {
    key: string;
}

export type insightUsageLogicType = MakeLogicType<insightUsageLogicValues, insightUsageLogicActions, InsightLogicProps, insightUsageLogicMeta>;

export const insightUsageLogic = kea<insightUsageLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['scenes', 'insights', 'insightUsageLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            projectLogic,
            ['currentProjectId'],
            userLogic,
            ['hasAvailableFeature'],
            insightLogic(props),
            ['insight'],
            dataNodeLogic({ key: insightVizDataNodeKey(props) } as DataNodeLogicProps),
            ['query'],
        ],
        actions: [eventUsageLogic, ['reportInsightViewed']],
    })),
    actions({
        onQueryChange: (query: Node | null, previousQuery?: Node | null) => ({
            query,
            previousQuery,
        }),
        setNotFirstLoad: true,
        recordNudgeView: true,
        requestInsightSubscriptionNudge: true,
    }),
    reducers({
        isFirstLoad: [
            true,
            {
                setNotFirstLoad: () => false,
            },
        ],
        nudgeViewTimestamps: [
            [] as number[],
            { persist: true },
            {
                recordNudgeView: (state) => {
                    const now = Date.now()
                    const cutoff = now - 7 * 24 * 60 * 60 * 1000
                    const fresh = state.filter((timestamp) => timestamp > cutoff)
                    const lastView = fresh[fresh.length - 1]
                    return lastView !== undefined && now - lastView < 60 * 1000 ? fresh : [...fresh, now]
                },
            },
        ],
        nudgeRequested: [
            false,
            { persist: true },
            {
                requestInsightSubscriptionNudge: () => true,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        onQueryChange: async ({ query }, breakpoint) => {
            // We only want to report direct views on the insights page.
            const logic = insightSceneLogic.findMounted()
            const shortId = logic?.values.insight?.short_id

            if (!logic || shortId !== values.insight?.short_id) {
                return
            }

            // Report the insight being viewed to our '/viewed' endpoint.
            // Used for "recently viewed insights", and in insights dashboard.
            if (values.insight.id && !isSharedView()) {
                void api.create(`api/environments/${values.currentProjectId}/insights/viewed`, {
                    insight_ids: [values.insight.id],
                })
            }

            // Debounce to avoid noisy events from the query changing multiple times.
            await breakpoint(IS_TEST_MODE ? 1 : 500)

            actions.reportInsightViewed(values.insight, query, values.isFirstLoad, 0)
            actions.setNotFirstLoad()
            actions.recordNudgeView()

            // Record a second view after 10 seconds.
            await breakpoint(IS_TEST_MODE ? 1 : 10000)

            actions.reportInsightViewed(values.insight, query, values.isFirstLoad, 10)
        },
        recordNudgeView: async () => {
            const insight = values.insight
            if (values.nudgeRequested || values.nudgeViewTimestamps.length < 3 || !insight.id || !insight.short_id) {
                return
            }
            if (posthog.getFeatureFlag('insight-subscribe-nudge') !== 'test') {
                return
            }

            const subscriptions = await subscriptionsList(String(getCurrentTeamId()), { insight: insight.id })
            if ((subscriptions.count ?? 0) > 0) {
                return
            }
            if (!values.hasAvailableFeature(AvailableFeature.SUBSCRIPTIONS)) {
                const teamSubscriptions = await subscriptionsList(String(getCurrentTeamId()))
                if ((teamSubscriptions.count ?? 0) >= SubscriptionFreeTierLimit.COUNT) {
                    return
                }
            }

            actions.requestInsightSubscriptionNudge()
            posthog.capture('insight subscribe nudge shown', {
                insight_id: insight.id,
                view_count_7d: values.nudgeViewTimestamps.length,
            })
            lemonToast.info(`You've viewed this insight ${values.nudgeViewTimestamps.length} times this week.`, {
                button: {
                    label: 'Set up subscription',
                    dataAttr: 'insight-subscribe-nudge-toast-cta',
                    action: () => {
                        posthog.capture('insight subscribe nudge clicked', { insight_id: insight.id, via: 'toast' })
                        router.actions.push(urlForSubscription('new', { insightShortId: insight.short_id }), {
                            [SUBSCRIPTION_PREFILL_PARAMS.param]: SUBSCRIPTION_PREFILL_PARAMS.nudge,
                            [SUBSCRIPTION_PREFILL_PARAMS.viaParam]: SUBSCRIPTION_PREFILL_PARAMS.viaToast,
                        })
                    },
                },
            })
        },
    })),
    subscriptions(({ actions }) => ({
        query: (query, oldQuery) => {
            if (objectsEqual(query, oldQuery)) {
                return
            }
            actions.onQueryChange(query, oldQuery)
        },
    })),
])
