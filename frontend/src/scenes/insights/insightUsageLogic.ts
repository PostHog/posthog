function reportInsightViewed(
    insightModel: Partial<InsightModel>,
    query: Node | null,
    isFirstLoad: boolean,
    delay?: number
): void {
    const payload: Record<string, any> = {
        report_delay: delay,
        is_first_component_load: isFirstLoad,
        viewer_is_creator:
            insightModel.created_by?.uuid && userLogic.values.user?.uuid
                ? insightModel.created_by?.uuid === userLogic.values.user?.uuid
                : undefined,
        is_saved: insightModel.saved,
        description_length: insightModel.description?.length ?? 0,
        tags_count: insightModel.tags?.length ?? 0,
        insight: sanitizeInsight(insightModel),
        insight_id: insightModel.id,
        insight_short_id: insightModel.short_id,
        ...sanitizeQuery(query),
    }

    // The view path passes a bare source node, so sanitizeQuery's `query_kind`/`query_source_kind`
    // describe the source rather than the wrapper. Override them from the full stored query so
    // `query_kind` consistently means the top-level node, matching every other insight event.
    const modelQuery = insightModel.query as Node | null | undefined
    if (modelQuery) {
        payload.query_kind = modelQuery.kind
        payload.query_source_kind = isNodeWithSource(modelQuery) ? modelQuery.source.kind : undefined
    }

    const eventName = delay ? 'insight analyzed' : 'insight viewed'
    posthog.capture(eventName, objectClean({ ...payload, source: 'web' }))
}

const IS_TEST_MODE = process.env.NODE_ENV === 'test'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightUsageLogicValues {
    query: DataNode<Record<string, any>> // dataNodeLogic
    insight: Partial<InsightModel<Node<Record<string, any>>>> // insightLogic
    savedInsight: Partial<InsightModel<Node<Record<string, any>>>>
    currentProjectId: number | null // projectLogic
    isFirstLoad: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightUsageLogicActions {
    onQueryChange: (
        query: Node | null,
        previousQuery?: Node | null
    ) => {
        previousQuery: Node<Record<string, any>> | null | undefined
        query: Node<Record<string, any>> | null
    }
    setNotFirstLoad: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface insightUsageLogicMeta {
    key: string
}

export type insightUsageLogicType = MakeLogicType<
    insightUsageLogicValues,
    insightUsageLogicActions,
    InsightLogicProps,
    insightUsageLogicMeta
>

export const insightUsageLogic = kea<insightUsageLogicType>([
    props({} as InsightLogicProps),
    key(keyForInsightLogicProps('new')),
    path((key) => ['scenes', 'insights', 'insightUsageLogic', key]),
    connect((props: InsightLogicProps) => ({
        values: [
            projectLogic,
            ['currentProjectId'],
            insightLogic(props),
            ['insight', 'savedInsight'],
            dataNodeLogic({ key: insightVizDataNodeKey(props) } as DataNodeLogicProps),
            ['query'],
        ],
    })),
    actions({
        onQueryChange: (query: Node | null, previousQuery?: Node | null) => ({
            query,
            previousQuery,
        }),
        setNotFirstLoad: true,
    }),
    reducers({
        isFirstLoad: [
            true,
            {
                setNotFirstLoad: () => false,
            },
        ],
    }),
    listeners(({ actions, props, values }) => ({
        onQueryChange: async ({ query }, breakpoint) => {
            // We only want to report direct views on the insights page.
            const logic = insightSceneLogic.findMounted()
            // Unsaved insights share an empty short_id, so it can't tell the scene's insight from a preview.
            const sceneDashboardItemId = logic?.values.insightLogicRef?.logic.props.dashboardItemId

            if (!logic || sceneDashboardItemId !== props.dashboardItemId) {
                return
            }

            // Report the insight being viewed to our '/viewed' endpoint.
            // Used for "recently viewed insights", and in insights dashboard.
            if (values.insight.id && values.currentProjectId && !isSharedView()) {
                const savedQuery = isNodeWithSource(values.savedInsight.query)
                    ? values.savedInsight.query.source
                    : values.savedInsight.query
                const matchesSavedContext =
                    savedQuery &&
                    objectsEqual(query, savedQuery) &&
                    !insightOverridesPresent(props.filtersOverride, props.variablesOverride, props.tileFiltersOverride)
                void insightsViewedCreate(String(values.currentProjectId), {
                    insight_ids: [values.insight.id],
                    query_context: matchesSavedContext ? (props.dashboardId ? 'dashboard' : 'standalone') : undefined,
                    dashboard_id: matchesSavedContext ? props.dashboardId : undefined,
                })
            }

            // Debounce to avoid noisy events from the query changing multiple times.
            await breakpoint(IS_TEST_MODE ? 1 : 500)

            reportInsightViewed(values.insight, query, values.isFirstLoad, 0)
            actions.setNotFirstLoad()

            // Record a second view after 10 seconds.
            await breakpoint(IS_TEST_MODE ? 1 : 10000)

            reportInsightViewed(values.insight, query, values.isFirstLoad, 10)
        },
    })),
    subscriptions(({ actions }) => ({
        query: (query, oldQuery) => {
            if (objectsEqual(query, oldQuery)) {
                return
            }
            actions.onQueryChange(query, oldQuery)
        },
    })),
])
