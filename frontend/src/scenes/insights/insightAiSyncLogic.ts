export const insightAiSyncLogic: LogicWrapper<insightAiSyncLogicType> = kea<insightAiSyncLogicType>([
    props({} as InsightAiSyncLogicProps),
    key(({ insightLogicProps }) => keyForInsightLogicProps('unloaded')(insightLogicProps)),
    path((key) => ['scenes', 'insights', 'insightAiSyncLogic', key]),
    connect(({ insightLogicProps }: InsightAiSyncLogicProps) => ({
        actions: [insightLogic(insightLogicProps), ['loadInsight', 'saveInsightSuccess']],
        values: [
            insightLogic(insightLogicProps),
            ['insight', 'insightChanged'],
            insightDataLogic(insightLogicProps),
            ['queryChanged'],
        ],
    })),
    actions({
        agentToolCompleted: (toolName: string, innerInput: Record<string, unknown> | null) => ({
            toolName,
            innerInput,
        }),
        setPendingAiConflict: true,
        keepMyChanges: true,
        useAiChanges: true,
    }),
    reducers({
        hasPendingAiConflict: [
            false,
            {
                setPendingAiConflict: () => true,
                keepMyChanges: () => false,
                useAiChanges: () => false,
                saveInsightSuccess: () => false,
            },
        ],
    }),
    listeners(({ actions, props, values }) => ({
        useAiChanges: () => {
            if (values.insight.short_id) {
                actions.loadInsight(
                    values.insight.short_id,
                    props.insightLogicProps.filtersOverride,
                    props.insightLogicProps.variablesOverride,
                    props.insightLogicProps.tileFiltersOverride
                )
            }
        },
        agentToolCompleted: ({ toolName, innerInput }) => {
            if (!innerInput || !values.insight.saved || !values.insight.id || !values.insight.short_id) {
                return
            }

            const targetsCurrentInsight =
                sameId(innerInput.id, values.insight.id) || sameId(innerInput.id, values.insight.short_id)

            if (toolName === 'insight-update' || toolName === 'insight-delete') {
                if (!targetsCurrentInsight) {
                    return
                }
                if (toolName === 'insight-delete') {
                    router.actions.push(urls.savedInsights())
                    return
                }
                if (values.insightChanged || values.queryChanged) {
                    actions.setPendingAiConflict()
                } else {
                    actions.useAiChanges()
                }
                return
            }

            const mountedSubscriptionsLogic = subscriptionsLogic.findMounted({
                insightShortId: values.insight.short_id,
            })
            if (toolName === 'subscriptions-create' && sameId(innerInput.insight, values.insight.id)) {
                mountedSubscriptionsLogic?.actions.loadAllSubscriptions()
                return
            }
            if (
                (toolName === 'subscriptions-partial-update' || toolName === 'subscriptions-delete') &&
                mountedSubscriptionsLogic &&
                [
                    ...mountedSubscriptionsLogic.values.subscriptions,
                    ...mountedSubscriptionsLogic.values.insightSubscriptions,
                ].some((subscription) => sameId(subscription.id, innerInput.id))
            ) {
                mountedSubscriptionsLogic.actions.loadAllSubscriptions()
                return
            }

            const mountedAlertLogics = insightAlertsLogic
                .findAllMounted()
                .filter((alertLogic) => sameId(alertLogic.props.insightId, values.insight.id))
            if (toolName === 'alert-create' && sameId(innerInput.insight, values.insight.id)) {
                mountedAlertLogics.forEach((alertLogic) => alertLogic.actions.loadAlerts())
                return
            }
            if (toolName === 'alert-update' || toolName === 'alert-delete') {
                mountedAlertLogics
                    .filter((alertLogic) => alertLogic.values.alerts.some((alert) => sameId(alert.id, innerInput.id)))
                    .forEach((alertLogic) => alertLogic.actions.loadAlerts())
            }
        },
    })),
])
