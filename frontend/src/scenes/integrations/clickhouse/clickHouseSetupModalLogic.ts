export const clickHouseSetupModalLogic = kea<clickHouseSetupModalLogicType>([
    path(['integrations', 'clickHouse', 'clickHouseSetupModalLogic']),
    props({} as ClickHouseSetupModalLogicProps),
    connect(() => ({
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    forms(({ props, actions, values }) => ({
        clickHouseIntegration: {
            defaults: {
                name: '' as string,
                host: '' as string,
                port: 8443,
                user: 'default' as string,
                password: '' as string,
                verify: true,
            },
            errors: ({ host, port, user, password }) => ({
                host: host.trim() ? undefined : 'Host is required',
                port: port ? undefined : 'Port is required',
                user: user.trim() ? undefined : 'User is required',
                password: password ? undefined : 'Password is required',
            }),
            submit: async () => {
                const { name, host, port, user, password, verify } = values.clickHouseIntegration
                try {
                    const integration = await integrationsCreate(String(getCurrentTeamId()), {
                        kind: 'clickhouse',
                        config: {
                            ...(name.trim() ? { name: name.trim() } : {}),
                            host: host.trim(),
                            port,
                            user: user.trim(),
                            password,
                            verify,
                        },
                    })
                    actions.loadIntegrations()
                    lemonToast.success('ClickHouse connection created')
                    props.onComplete(integration.id)
                } catch (error: any) {
                    lemonToast.error(
                        error.detail || 'Could not create the ClickHouse connection. Check the details and try again.'
                    )
                    throw error
                }
            },
        },
    })),
])
