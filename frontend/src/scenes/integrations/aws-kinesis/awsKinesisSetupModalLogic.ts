export const awsKinesisSetupModalLogic = kea<awsKinesisSetupModalLogicType>([
    path(['integrations', 'aws-kinesis', 'awsKinesisSetupModalLogic']),
    props({} as AwsKinesisSetupModalLogicProps),
    connect(() => ({
        values: [teamLogic, ['currentTeamIdStrict']],
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        setAuthMode: (mode: KinesisAuthMode) => ({ mode }),
    }),
    reducers({
        authMode: [
            'role' as KinesisAuthMode,
            {
                setAuthMode: (_, { mode }) => mode,
            },
        ],
    }),
    forms(({ props, actions, values }) => ({
        awsKinesisIntegration: {
            defaults: {
                name: '',
                awsAccessKeyId: '',
                awsSecretAccessKey: '',
                awsRoleArn: '',
            },
            errors: ({ name, awsAccessKeyId, awsSecretAccessKey, awsRoleArn }) => ({
                name: name.trim() ? undefined : 'Name is required',
                awsAccessKeyId:
                    values.authMode === 'role' || awsAccessKeyId.trim() ? undefined : 'Access Key ID is required',
                awsSecretAccessKey:
                    values.authMode === 'role' || awsSecretAccessKey.trim()
                        ? undefined
                        : 'Secret Access Key is required',
                awsRoleArn:
                    values.authMode !== 'role'
                        ? undefined
                        : !awsRoleArn.trim()
                          ? 'IAM role ARN is required'
                          : !IAM_ROLE_ARN_REGEX.test(awsRoleArn.trim())
                            ? 'Enter a valid IAM role ARN, e.g. arn:aws:iam::123456789012:role/my-role'
                            : undefined,
            }),
            submit: async () => {
                try {
                    const { name, awsAccessKeyId, awsSecretAccessKey, awsRoleArn } = values.awsKinesisIntegration
                    const integration = await integrationsCreate(String(values.currentTeamIdStrict), {
                        kind: 'aws-kinesis',
                        config:
                            values.authMode === 'role'
                                ? {
                                      name,
                                      aws_role_arn: awsRoleArn.trim(),
                                  }
                                : {
                                      name,
                                      aws_access_key_id: awsAccessKeyId,
                                      aws_secret_access_key: awsSecretAccessKey,
                                  },
                    })
                    actions.loadIntegrations()
                    lemonToast.success('AWS Kinesis connection created.')
                    props.onComplete(integration.id)
                } catch (error: any) {
                    lemonToast.error(error.detail || 'Failed to create the AWS Kinesis connection. Try again.')
                    throw error
                }
            },
        },
    })),
    listeners(({ actions }) => ({
        setAuthMode: () => {
            actions.setAwsKinesisIntegrationValues({
                awsAccessKeyId: '',
                awsSecretAccessKey: '',
                awsRoleArn: '',
            })
        },
    })),
])
