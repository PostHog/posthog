export type motherDuckSetupModalLogicType = MakeLogicType<
    motherDuckSetupModalLogicValues,
    motherDuckSetupModalLogicActions,
    MotherDuckSetupModalLogicProps
>

export const motherDuckSetupModalLogic = kea<motherDuckSetupModalLogicType>([
    path(['integrations', 'motherduck', 'motherDuckSetupModalLogic']),
    props({} as MotherDuckSetupModalLogicProps),
    connect(() => ({
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    forms(({ props, actions, values }) => ({
        motherDuckIntegration: {
            defaults: {
                name: '',
                access_token: '',
            } as MotherDuckIntegrationForm,
            errors: ({ name, access_token }) => ({
                name: name.trim() ? undefined : 'Name is required',
                access_token: access_token.trim() ? undefined : 'Access token is required',
            }),
            submit: async () => {
                const { name, access_token } = values.motherDuckIntegration
                try {
                    const integration = await integrationsCreate(String(ApiConfig.getCurrentProjectId()), {
                        kind: 'motherduck',
                        config: { name: name.trim(), access_token: access_token.trim() },
                    })
                    actions.loadIntegrations()
                    lemonToast.success('MotherDuck connection created successfully!')
                    props.onComplete(integration.id)
                } catch (error: any) {
                    lemonToast.error(error.detail || 'Failed to create MotherDuck connection')
                    throw error
                }
            },
        },
    })),
])
