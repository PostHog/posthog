export const awsWarehouseSourcesSetupModalLogic = kea<awsWarehouseSourcesSetupModalLogicType>([
    path(['integrations', 'aws-warehouse-sources', 'awsWarehouseSourcesSetupModalLogic']),
    props({} as AwsWarehouseSourcesSetupModalLogicProps),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    forms(({ props, actions, values }) => ({
        awsWarehouseSourcesIntegration: {
            defaults: {
                name: '',
                awsRoleArn: '',
            },
            errors: ({ name, awsRoleArn }) => ({
                name: name.trim() ? undefined : 'Name is required',
                awsRoleArn: !awsRoleArn.trim()
                    ? 'IAM role ARN is required'
                    : !IAM_ROLE_ARN_REGEX.test(awsRoleArn.trim())
                      ? 'Enter a valid IAM role ARN, e.g. arn:aws:iam::123456789012:role/my-role'
                      : undefined,
            }),
            submit: async ({ name, awsRoleArn }) => {
                try {
                    const integration = await integrationsCreate(String(values.currentProjectId), {
                        // TODO: drop the cast once the generated kind enum lists aws-warehouse-sources.
                        kind: 'aws-warehouse-sources' as IntegrationKindEnumApi,
                        config: { name, aws_role_arn: awsRoleArn.trim() },
                    })
                    actions.loadIntegrations()
                    lemonToast.success('AWS role connection created')
                    props.onComplete(integration.id)
                } catch (error: any) {
                    lemonToast.error(error.detail || "Couldn't create the AWS role connection. Try again.")
                    throw error
                }
            },
        },
    })),
])
