export const githubConnectSceneLogic = kea<githubConnectSceneLogicType>([
    path(['scenes', 'integrations', 'github-connect', 'githubConnectSceneLogic']),
    connect(() => ({
        values: [
            integrationsLogic,
            [
                'integrations',
                'githubIntegrations',
                'githubAvailableInstallations',
                'githubAvailableInstallationsResponse',
                'githubDiscoveryFailed',
                'linkedGithubInstallationLoading',
                'integrationsLoading',
            ],
            teamLogic,
            ['currentProjectId'],
        ],
        actions: [
            integrationsLogic,
            [
                'loadIntegrations',
                'loadIntegrationsFailure',
                'loadIntegrationsSuccess',
                'subscribeGithubSuggestions',
                'unsubscribeGithubSuggestions',
                'linkExistingGithubInstallation',
            ],
            eventUsageLogic,
            ['reportIntegrationConnectClicked', 'reportGithubInstallationSelected'],
        ],
    })),
    actions({
        continueToGithub: true,
        githubRedirectInterrupted: true,
        linkInstallation: (installationId: string | undefined) => ({ installationId }),
    }),
    reducers({
        redirectingToGithub: [
            false,
            {
                continueToGithub: () => true,
                githubRedirectInterrupted: () => false,
            },
        ],
        integrationsLoadFailed: [
            false,
            {
                loadIntegrations: () => false,
                loadIntegrationsSuccess: () => false,
                loadIntegrationsFailure: () => true,
            },
        ],
    }),
    selectors({
        status: [
            (s) => [s.integrations, s.githubAvailableInstallations, s.githubDiscoveryFailed, s.integrationsLoadFailed],
            (
                integrations: IntegrationType[] | null,
                githubAvailableInstallations: GitHubAvailableInstallationApi[] | null,
                githubDiscoveryFailed: boolean,
                integrationsLoadFailed: boolean
            ): GitHubConnectStatus =>
                githubConnectStatus(
                    integrations,
                    githubAvailableInstallations,
                    githubDiscoveryFailed,
                    integrationsLoadFailed
                ),
        ],
        authorizeUrl: [
            (s) => [s.currentProjectId],
            (currentProjectId: number | string): string =>
                `${getIntegrationsAuthorizeRetrieveUrl(String(currentProjectId))}?${new URLSearchParams({
                    kind: 'github',
                    next: GITHUB_CONNECT_RETURN_PATH,
                })}`,
        ],
    }),
    listeners(({ actions, values }) => ({
        continueToGithub: () => {
            actions.reportIntegrationConnectClicked('github', 'github', 'chat_connect_page')
            window.location.href = values.authorizeUrl
        },
        linkInstallation: ({ installationId }) => {
            const response = values.githubAvailableInstallationsResponse
            actions.reportIntegrationConnectClicked('github', 'github', 'chat_connect_page')
            actions.reportGithubInstallationSelected(
                'chat_connect_page',
                response?.discovery_id,
                installationId,
                Math.max(0, Date.now() - Date.parse(response?.discovered_at ?? ''))
            )
            actions.linkExistingGithubInstallation(installationId)
        },
    })),
    afterMount(({ actions, cache }) => {
        actions.subscribeGithubSuggestions()
        // Going back from GitHub can restore this page from the back-forward cache with the
        // button still loading, so clear it when the browser shows the cached page.
        cache.disposables.add(
            () => {
                const onPageShow = (event: PageTransitionEvent): void => {
                    if (event.persisted) {
                        actions.githubRedirectInterrupted()
                    }
                }
                window.addEventListener('pageshow', onPageShow)
                return () => window.removeEventListener('pageshow', onPageShow)
            },
            'pageshow',
            { pauseOnPageHidden: false }
        )
    }),
    beforeUnmount(({ actions }) => {
        actions.unsubscribeGithubSuggestions()
    }),
])
