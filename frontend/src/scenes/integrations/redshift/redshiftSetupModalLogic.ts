import { MakeLogicType, actions, connect, kea, listeners, path, props, reducers } from 'kea'
import { forms } from 'kea-forms'
import type { DeepPartial, DeepPartialMap, FieldName, ValidationErrorType } from 'kea-forms'

import api from 'lib/api'
import { integrationsLogic } from 'lib/integrations/integrationsLogic'
import { lemonToast } from 'lib/lemon-ui/LemonToast'

import type { IntegrationType } from '~/types'

export type RedshiftAuthMode = 'password' | 'iam_role'

const IAM_ROLE_ARN_REGEX = /^arn:aws:iam::\d{12}:role\/.+$/

export interface RedshiftSetupModalLogicProps {
    isOpen: boolean
    integration?: IntegrationType | null
    onComplete: (integrationId?: number) => void
}

type RedshiftIntegrationForm = {
    awsRoleArn: string
    name: string
    password: string
    user: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface redshiftSetupModalLogicValues {
    authMode: RedshiftAuthMode
    isRedshiftIntegrationSubmitting: boolean
    isRedshiftIntegrationValid: boolean
    redshiftIntegration: RedshiftIntegrationForm
    redshiftIntegrationAllErrors: Record<string, any>
    redshiftIntegrationChanged: boolean
    redshiftIntegrationErrors: DeepPartialMap<RedshiftIntegrationForm, ValidationErrorType>
    redshiftIntegrationHasErrors: boolean
    redshiftIntegrationManualErrors: Record<string, any>
    redshiftIntegrationTouched: boolean
    redshiftIntegrationTouches: Record<string, boolean>
    redshiftIntegrationValidationErrors: DeepPartialMap<RedshiftIntegrationForm, ValidationErrorType>
    showRedshiftIntegrationErrors: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface redshiftSetupModalLogicActions {
    loadIntegrations: () => any
    resetRedshiftIntegration: (values?: RedshiftIntegrationForm) => { values?: RedshiftIntegrationForm }
    setAuthMode: (mode: RedshiftAuthMode) => { mode: RedshiftAuthMode }
    setRedshiftIntegrationManualErrors: (errors: Record<string, any>) => { errors: Record<string, any> }
    setRedshiftIntegrationValue: (key: FieldName, value: any) => { name: FieldName; value: any }
    setRedshiftIntegrationValues: (values: DeepPartial<RedshiftIntegrationForm>) => {
        values: DeepPartial<RedshiftIntegrationForm>
    }
    submitRedshiftIntegration: () => { value: boolean }
    submitRedshiftIntegrationFailure: (
        error: Error,
        errors: Record<string, any>
    ) => {
        error: Error
        errors: Record<string, any>
    }
    submitRedshiftIntegrationRequest: (redshiftIntegration: RedshiftIntegrationForm) => {
        redshiftIntegration: RedshiftIntegrationForm
    }
    submitRedshiftIntegrationSuccess: (redshiftIntegration: RedshiftIntegrationForm) => {
        redshiftIntegration: RedshiftIntegrationForm
    }
    touchRedshiftIntegrationField: (key: string) => { key: string }
}

export type redshiftSetupModalLogicType = MakeLogicType<
    redshiftSetupModalLogicValues,
    redshiftSetupModalLogicActions,
    RedshiftSetupModalLogicProps
>

export const redshiftSetupModalLogic = kea<redshiftSetupModalLogicType>([
    path(['integrations', 'redshift', 'redshiftSetupModalLogic']),
    props({} as RedshiftSetupModalLogicProps),
    connect(() => ({
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        setAuthMode: (mode: RedshiftAuthMode) => ({ mode }),
    }),
    reducers({
        authMode: [
            'password' as RedshiftAuthMode,
            {
                setAuthMode: (_, { mode }) => mode,
            },
        ],
    }),
    forms(({ props, actions, values }) => ({
        redshiftIntegration: {
            defaults: {
                name: '',
                user: '',
                password: '',
                awsRoleArn: '',
            },
            errors: ({ name, user, password, awsRoleArn }) => ({
                name: name.trim() ? undefined : 'Name is required',
                user: values.authMode === 'iam_role' || user.trim() ? undefined : 'User is required',
                password: values.authMode === 'iam_role' || password.trim() ? undefined : 'Password is required',
                awsRoleArn:
                    values.authMode === 'password'
                        ? undefined
                        : !awsRoleArn.trim()
                          ? 'IAM role ARN is required'
                          : !IAM_ROLE_ARN_REGEX.test(awsRoleArn.trim())
                            ? 'Enter a valid IAM role ARN, e.g. arn:aws:iam::123456789012:role/my-role'
                            : undefined,
            }),
            submit: async () => {
                try {
                    const { name, user, password, awsRoleArn } = values.redshiftIntegration
                    const integration = await api.integrations.create({
                        kind: 'redshift',
                        config:
                            values.authMode === 'password'
                                ? {
                                      name,
                                      authentication_type: 'password',
                                      user,
                                      password,
                                  }
                                : {
                                      name,
                                      authentication_type: 'iam_role',
                                      aws_role_arn: awsRoleArn.trim(),
                                  },
                    })
                    actions.loadIntegrations()
                    lemonToast.success('Redshift connection created successfully!')
                    props.onComplete(integration.id)
                } catch (error: any) {
                    lemonToast.error(error.detail || 'Failed to create Redshift connection')
                    throw error
                }
            },
        },
    })),
    listeners(({ actions }) => ({
        setAuthMode: () => {
            actions.setRedshiftIntegrationValues({
                user: '',
                password: '',
                awsRoleArn: '',
            })
        },
    })),
])
