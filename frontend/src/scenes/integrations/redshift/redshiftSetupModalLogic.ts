export const redshiftSetupModalLogic = kea<redshiftSetupModalLogicType>([
    path(['integrations', 'redshift', 'redshiftSetupModalLogic']),
    props({} as RedshiftSetupModalLogicProps),
    connect(() => ({
        actions: [integrationsLogic, ['loadIntegrations']],
    })),
    actions({
        setAuthMode: (mode: RedshiftAuthMode) => ({ mode }),
    }),
    reducers({
        authMode: [
            'role' as RedshiftAuthMode,
            {
                setAuthMode: (_, { mode }) => mode,
            },
        ],
    }),
    forms(({ props, actions, values }) => ({
        redshiftIntegration: {
            defaults: {
                name: '',
                user: '',
                awsRoleArn: '',
                awsAccessKeyId: '',
                awsSecretAccessKey: '',
                groups: [] as string[],
                autoCreate: false as boolean,
                workgroupArn: '',
                host: '',
                port: 5439,
                password: '',
                sslMode: 'require',
                useSystemCa: true as boolean,
                sslRootCert: '',
            },
            errors: ({
                name,
                user,
                awsRoleArn,
                awsAccessKeyId,
                awsSecretAccessKey,
                workgroupArn,
                host,
                port,
                password,
                sslMode,
                useSystemCa,
                sslRootCert,
            }) => {
                const isAws = values.authMode !== 'password'
                return {
                    name: !isAws || name.trim() ? undefined : 'Name is required',
                    user: user.trim() ? undefined : 'User is required',
                    awsRoleArn:
                        values.authMode !== 'role'
                            ? undefined
                            : !awsRoleArn.trim()
                              ? 'IAM role ARN is required'
                              : !IAM_ROLE_ARN_REGEX.test(awsRoleArn.trim())
                                ? 'Enter a valid IAM role ARN, e.g. arn:aws:iam::123456789012:role/my-role'
                                : undefined,
                    awsAccessKeyId:
                        values.authMode !== 'access_key' || awsAccessKeyId.trim()
                            ? undefined
                            : 'Access key ID is required',
                    awsSecretAccessKey:
                        values.authMode !== 'access_key' || awsSecretAccessKey.trim()
                            ? undefined
                            : 'Secret access key is required',
                    workgroupArn:
                        !isAws || !workgroupArn.trim() || SERVERLESS_WORKGROUP_ARN_REGEX.test(workgroupArn.trim())
                            ? undefined
                            : 'Enter a valid workgroup ARN, e.g. arn:aws:redshift-serverless:us-east-1:123456789012:workgroup/my-workgroup',
                    host: isAws || host.trim() ? undefined : 'Host is required',
                    port: isAws || port ? undefined : 'Port is required',
                    password: isAws || password.trim() ? undefined : 'Password is required',
                    sslRootCert:
                        isAws || sslMode === 'require' || useSystemCa || sslRootCert.trim()
                            ? undefined
                            : 'Upload a root certificate, or use the system certificate authorities',
                }
            },
            submit: async () => {
                const {
                    name,
                    user,
                    awsRoleArn,
                    awsAccessKeyId,
                    awsSecretAccessKey,
                    groups,
                    autoCreate,
                    workgroupArn,
                    host,
                    port,
                    password,
                    sslMode,
                    useSystemCa,
                    sslRootCert,
                } = values.redshiftIntegration

                const awsConfig = {
                    name,
                    user: user.trim(),
                    auto_create: autoCreate,
                    ...(groups.length ? { groups } : {}),
                    ...(workgroupArn.trim() ? { workgroup_arn: workgroupArn.trim() } : {}),
                }

                const config =
                    values.authMode === 'role'
                        ? { ...awsConfig, aws_role_arn: awsRoleArn.trim() }
                        : values.authMode === 'access_key'
                          ? {
                                ...awsConfig,
                                aws_access_key_id: awsAccessKeyId.trim(),
                                aws_secret_access_key: awsSecretAccessKey,
                            }
                          : {
                                host: host.trim(),
                                port,
                                user: user.trim(),
                                password,
                                ssl_mode: sslMode,
                                ...(sslMode !== 'require'
                                    ? { ssl_root_cert: useSystemCa ? 'system' : sslRootCert }
                                    : {}),
                            }

                try {
                    const integration = await api.integrations.create({ kind: 'aws-redshift', config })
                    actions.loadIntegrations()
                    lemonToast.success('Redshift connection created')
                    props.onComplete(integration.id)
                } catch (error: any) {
                    lemonToast.error(error.detail || 'Failed to create the Redshift connection')
                    throw error
                }
            },
        },
    })),
    listeners(({ actions }) => ({
        setAuthMode: () => {
            actions.setRedshiftIntegrationValues({
                awsRoleArn: '',
                awsAccessKeyId: '',
                awsSecretAccessKey: '',
                password: '',
                sslRootCert: '',
            })
        },
    })),
])
