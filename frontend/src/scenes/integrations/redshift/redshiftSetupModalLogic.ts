/**
 * The `aws-redshift` integration kind covers three backend classes, told apart only by which config
 * keys the create request carries: `aws_role_arn` picks the role-based one, an access key pair picks
 * the credentials one, and host/port/user/password picks the plain Postgres-wire one. Each mode
 * below must send exactly its own keys, or the wrong class handles the request.
 */
export type RedshiftAuthMode = 'role' | 'access_key' | 'password'

// Partition suffixes (aws-cn, aws-us-gov) are allowed, matching AWS_ROLE_ARN_RE on the backend.
const IAM_ROLE_ARN_REGEX = /^arn:aws(-[a-z-]+)?:iam::\d{12}:role\/.+$/
const SERVERLESS_WORKGROUP_ARN_REGEX = /^arn:aws(-[a-z-]+)?:redshift-serverless:[a-z0-9-]+:\d{12}:workgroup\/.+$/

