export const taskAgentDefaultsLogic = kea<taskAgentDefaultsLogicType>([
    path(['scenes', 'settings', 'environment', 'taskAgentDefaultsLogic']),

    connect(() => ({
        // `taskRunDefaultsLogic` already owns reading `@me/config` for the composers, and its
        // resolution is what this page is editing — sharing it keeps one cache and one fetch
        // instead of two that drift.
        values: [
            projectLogic,
            ['currentProjectId'],
            taskRunDefaultsLogic,
            ['myConfig', 'resolvedDefaults'],
            modelCatalogueLogic,
            ['catalogue'],
        ],
        actions: [taskRunDefaultsLogic, ['loadMyConfig', 'loadMyConfigSuccess']],
    })),

    actions({
        setTeamDraft: (draft: Partial<AIRunPreferenceDraft>) => ({ draft }),
        setMyDraft: (draft: Partial<AIRunPreferenceDraft>) => ({ draft }),
        submitTeamDraft: true,
        submitMyDraft: true,
        resetMyPreference: true,
    }),

    // Each card's draft carries a `touched` flag in the same reducer, so a load result can be
    // gated right where it lands: a refetch (the team save triggers one, and the shared
    // `myConfig` loader can resolve mid-edit) must never overwrite a pick someone is in the
    // middle of making. Saves untouch the draft — the stored value is the edit again.
    reducers({
        teamDraftState: [
            UNTOUCHED_EMPTY_DRAFT,
            {
                setTeamDraft: (state, { draft }) => ({ draft: { ...state.draft, ...draft }, touched: true }),
                loadTeamPreferencesSuccess: (state, { teamPreferences }) =>
                    state.touched ? state : { draft: draftFromStored(teamPreferences), touched: false },
                saveTeamPreferencesSuccess: (_, { teamPreferences }) => ({
                    draft: draftFromStored(teamPreferences),
                    touched: false,
                }),
            },
        ],
        myDraftState: [
            UNTOUCHED_EMPTY_DRAFT,
            {
                setMyDraft: (state, { draft }) => ({ draft: { ...state.draft, ...draft }, touched: true }),
                loadMyConfigSuccess: (state, { myConfig }) =>
                    state.touched ? state : { draft: draftFromStored(myConfig?.ai_run_preferences), touched: false },
                saveMyPreferencesSuccess: (_, { myPreferences }) => ({
                    draft: draftFromStored(myPreferences?.ai_run_preferences),
                    touched: false,
                }),
            },
        ],
    }),

    loaders(({ values }) => ({
        teamPreferences: {
            __default: null as TasksAIRunPreferencesApi | null,
            loadTeamPreferences: async (): Promise<TasksAIRunPreferencesApi | null> => {
                if (values.currentProjectId == null) {
                    return null
                }
                return (await tasksConfigList(String(values.currentProjectId))).ai_run_preferences
            },
            saveTeamPreferences: async (
                preferences: TasksAIRunPreferencesApi
            ): Promise<TasksAIRunPreferencesApi | null> => {
                const response = await tasksConfigCreate(String(values.currentProjectId), preferences)
                lemonToast.success(preferences.model ? 'Project default saved' : 'Project default cleared')
                return response.ai_run_preferences
            },
        },
        myPreferences: {
            __default: null as TasksUserConfigResponseApi | null,
            saveMyPreferences: async (
                preferences: TasksAIRunPreferencesApi
            ): Promise<TasksUserConfigResponseApi | null> => {
                const response = await tasksMeConfigCreate(String(values.currentProjectId), preferences)
                lemonToast.success(preferences.model ? 'Your default saved' : 'Reset to the project default')
                return response
            },
        },
    })),

    selectors({
        teamDraft: [(s) => [s.teamDraftState], (state: DraftState): AIRunPreferenceDraft => state.draft],
        myDraft: [(s) => [s.myDraftState], (state: DraftState): AIRunPreferenceDraft => state.draft],
        // The save response is read first so the reset button settles in the same tick as the
        // save; `myConfig` (refreshed alongside it) is what's there on mount and after a
        // project-level write.
        myPreferenceStored: [
            (s) => [s.myPreferences, s.myConfig],
            (saved: TasksUserConfigResponseApi | null, loaded: TasksUserConfigResponseApi | null) =>
                draftFromStored((saved ?? loaded)?.ai_run_preferences),
        ],
        // Whether there's anything to send.
        teamDraftDirty: [
            (s) => [s.teamDraft, s.teamPreferences],
            (draft: AIRunPreferenceDraft, stored: TasksAIRunPreferencesApi | null): boolean =>
                isDraftChanged(draft, draftFromStored(stored)),
        ],
        myDraftDirty: [
            (s) => [s.myDraft, s.myPreferenceStored],
            (draft: AIRunPreferenceDraft, stored: AIRunPreferenceDraft): boolean => isDraftChanged(draft, stored),
        ],
        // Nothing to fall back to when neither the draft nor the stored preference pins a model — the
        // effort alone is never stored without one.
        canResetMyPreference: [
            (s) => [s.myDraft, s.myPreferenceStored],
            (draft: AIRunPreferenceDraft, stored: AIRunPreferenceDraft): boolean =>
                Boolean(draft.model || stored.model),
        ],
    }),

    listeners(({ actions, values }) => ({
        submitTeamDraft: () => {
            actions.saveTeamPreferences(payloadFromDraft(values.teamDraft, values.catalogue))
        },
        submitMyDraft: () => {
            actions.saveMyPreferences(payloadFromDraft(values.myDraft, values.catalogue))
        },
        // Clearing the stored preference is what hands the choice back to the project default, so the
        // reset discards any unsaved edit and saves the empty draft in one go.
        resetMyPreference: () => {
            actions.setMyDraft(EMPTY_DRAFT)
            actions.saveMyPreferences(payloadFromDraft(EMPTY_DRAFT, values.catalogue))
        },
        // Both writes change what an unpinned run resolves to, so the shared read the composers
        // render from has to move too. The team write can't say what the user-level answer
        // becomes, so it refetches; the personal write already has it in its own response.
        saveTeamPreferencesSuccess: () => {
            actions.loadMyConfig()
        },
        saveMyPreferencesSuccess: ({ myPreferences }) => {
            if (myPreferences) {
                actions.loadMyConfigSuccess(myPreferences)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadTeamPreferences()
    }),
])
