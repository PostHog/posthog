export const agentInstructionsSettingsLogic = kea<agentInstructionsSettingsLogicType>([
    path(['scenes', 'settings', 'environment', 'agentInstructionsSettingsLogic']),

    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),

    actions({
        setProjectDraft: (draft: string) => ({ draft }),
        setPersonalDraft: (draft: string) => ({ draft }),
        submitProjectDraft: true,
        submitPersonalDraft: true,
    }),

    loaders(({ values }) => ({
        projectInstructions: {
            __default: null as string | null,
            loadProjectInstructions: async (): Promise<string | null> => {
                if (values.currentProjectId == null) {
                    return null
                }
                return (await tasksConfigList(String(values.currentProjectId))).agent_instructions
            },
            saveProjectInstructions: async (instructions: string): Promise<string | null> => {
                const response = await tasksConfigAgentInstructionsCreate(String(values.currentProjectId), {
                    agent_instructions: instructions,
                })
                lemonToast.success(instructions.trim() ? 'Project instructions saved' : 'Project instructions cleared')
                return response.agent_instructions
            },
        },
        personalInstructions: {
            __default: null as string | null,
            loadPersonalInstructions: async (): Promise<string | null> => {
                if (values.currentProjectId == null) {
                    return null
                }
                return (await tasksMeConfigList(String(values.currentProjectId))).agent_instructions
            },
            savePersonalInstructions: async (instructions: string): Promise<string | null> => {
                const response = await tasksMeConfigAgentInstructionsCreate(String(values.currentProjectId), {
                    agent_instructions: instructions,
                })
                lemonToast.success(instructions.trim() ? 'Your instructions saved' : 'Your instructions cleared')
                return response.agent_instructions
            },
        },
    })),

    // A draft is null while untouched, so a load landing mid-edit never replaces what someone is typing.
    reducers({
        projectDraft: [
            null as string | null,
            {
                setProjectDraft: (_, { draft }) => draft,
                saveProjectInstructionsSuccess: () => null,
            },
        ],
        personalDraft: [
            null as string | null,
            {
                setPersonalDraft: (_, { draft }) => draft,
                savePersonalInstructionsSuccess: () => null,
            },
        ],
    }),

    selectors({
        projectValue: [
            (s) => [s.projectDraft, s.projectInstructions],
            (draft: string | null, stored: string | null): string => draft ?? stored ?? '',
        ],
        personalValue: [
            (s) => [s.personalDraft, s.personalInstructions],
            (draft: string | null, stored: string | null): string => draft ?? stored ?? '',
        ],
        projectDirty: [
            (s) => [s.projectDraft, s.projectInstructions],
            (draft: string | null, stored: string | null): boolean => draft !== null && draft !== (stored ?? ''),
        ],
        personalDirty: [
            (s) => [s.personalDraft, s.personalInstructions],
            (draft: string | null, stored: string | null): boolean => draft !== null && draft !== (stored ?? ''),
        ],
    }),

    listeners(({ actions, values }) => ({
        submitProjectDraft: () => {
            actions.saveProjectInstructions(values.projectValue)
        },
        submitPersonalDraft: () => {
            actions.savePersonalInstructions(values.personalValue)
        },
        saveProjectInstructionsSuccess: ({ projectInstructions }) => {
            trackSaved('project', projectInstructions ?? '')
        },
        savePersonalInstructionsSuccess: ({ personalInstructions }) => {
            trackSaved('personal', personalInstructions ?? '')
        },
    })),

    afterMount(({ actions }) => {
        actions.loadProjectInstructions()
        actions.loadPersonalInstructions()
    }),
])
