export type AgentInstructionsScope = 'project' | 'personal'

function trackSaved(scope: AgentInstructionsScope, instructions: string): void {
    // pinned: analytics event name and properties, renaming breaks dashboards
    posthog.capture('agent instructions saved', {
        scope,
        length: instructions.length,
        cleared: instructions.trim().length === 0,
    })
}

