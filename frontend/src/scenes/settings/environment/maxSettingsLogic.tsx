export const maxSettingsLogic = kea<maxSettingsLogicType>([
    path(['scenes', 'project', 'Settings', 'maxSettingsLogic']),

    actions({
        setIsLoading: (isLoading: boolean) => ({ isLoading }),
        trimCoreMemoryToFit: true,
    }),

    reducers({
        isLoading: [
            false,
            {
                loadCoreMemory: () => true,
                loadCoreMemorySuccess: () => false,
                loadCoreMemoryFailure: () => false,
            },
        ],

        coreMemoryLoadError: [
            null as string | null,
            {
                loadCoreMemory: () => null,
                loadCoreMemorySuccess: () => null,
                loadCoreMemoryFailure: (_, { error }) => error || 'Could not load memory.',
            },
        ],

        isUpdating: [
            false,
            {
                createCoreMemory: () => true,
                createCoreMemorySuccess: () => false,
                createCoreMemoryFailure: () => false,
                updateCoreMemory: () => true,
                updateCoreMemorySuccess: () => false,
                updateCoreMemoryFailure: () => false,
            },
        ],
    }),

    loaders(({ values }) => ({
        coreMemory: {
            __default: null as CoreMemory | null,
            loadCoreMemory: async (): Promise<CoreMemory | null> => {
                // Let HTTP errors (403, timeout) reach loadCoreMemoryFailure so the UI can show a real
                // error with a retry, rather than an empty textarea that reads as "my memory is gone".
                // An empty result list is a genuine "no memory yet" state and still resolves to null.
                const response = await api.coreMemory.list()
                return response.results[0] || null
            },
            updateCoreMemory: async (data: CoreMemoryForm) => {
                if (!values.coreMemory) {
                    const response = await api.coreMemory.create(data)
                    lemonToast.success('PostHog AI memory has been created.')
                    posthog.capture('core memory saved', { action: 'create', length: data.text.length })
                    return response
                }

                const response = await api.coreMemory.update(values.coreMemory.id, data)
                lemonToast.success('PostHog AI memory has been updated.')
                posthog.capture('core memory saved', { action: 'update', length: data.text.length })
                return response
            },
        },
    })),

    forms(({ actions }) => ({
        coreMemoryForm: {
            defaults: { text: '' } as CoreMemoryForm,
            submit: ({ text }) => {
                actions.updateCoreMemory({ text })
            },
        },
    })),

    selectors({
        coreMemoryOverLimit: [
            (s) => [s.coreMemoryForm],
            (coreMemoryForm: CoreMemoryForm) => (coreMemoryForm?.text?.length ?? 0) > CORE_MEMORY_MAX_CHARACTERS,
        ],
    }),

    listeners(({ actions, values }) => ({
        loadCoreMemorySuccess: ({ coreMemory }) => {
            if (coreMemory) {
                actions.setCoreMemoryFormValue('text', coreMemory.text)
            }
        },
        loadCoreMemoryFailure: ({ errorObject }) => {
            posthog.capture('core memory load failed', {
                status: errorObject instanceof ApiError ? errorObject.status : undefined,
                access_denied: errorObject instanceof ApiError ? isAccessDeniedError(errorObject) : undefined,
            })
        },
        trimCoreMemoryToFit: () => {
            const trimmed = (values.coreMemoryForm?.text ?? '').slice(0, CORE_MEMORY_MAX_CHARACTERS)
            actions.setCoreMemoryFormValue('text', trimmed)
            posthog.capture('core memory trimmed to fit', { length: trimmed.length })
        },
        updateCoreMemoryFailure: ({ error, errorObject }) => {
            const detail = errorObject instanceof ApiError ? errorObject.detail : null
            lemonToast.error(detail || error || 'Could not save memory.')
            posthog.capture('core memory save failed', {
                status: errorObject instanceof ApiError ? errorObject.status : undefined,
                over_limit: values.coreMemoryOverLimit,
            })
        },
    })),

    afterMount(({ actions }) => {
        actions.loadCoreMemory()
    }),
])
