export type cloudEnvironmentsLogicType = MakeLogicType<
    cloudEnvironmentsLogicValues,
    cloudEnvironmentsLogicActions,
    Record<string, any>,
    cloudEnvironmentsLogicMeta
>

export const cloudEnvironmentsLogic = kea<cloudEnvironmentsLogicType>([
    path(['scenes', 'settings', 'environment', 'cloudEnvironmentsLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    actions({
        startNewEnvironment: true,
        editEnvironment: (environment: SandboxEnvironmentDTOApi) => ({ environment }),
        updateDraft: (changes: Partial<CloudEnvironmentDraft>) => ({ changes }),
        closeDraft: true,
        saveDraft: true,
        saveDraftDone: true,
        deleteEnvironment: (environment: SandboxEnvironmentDTOApi) => ({ environment }),
    }),
    loaders(({ values }) => ({
        environments: [
            null as SandboxEnvironmentDTOApi[] | null,
            {
                loadEnvironments: async (): Promise<SandboxEnvironmentDTOApi[] | null> => {
                    if (values.currentProjectId == null) {
                        return null
                    }
                    const page = await sandboxList(String(values.currentProjectId))
                    return page.results
                },
            },
        ],
    })),
    reducers({
        draft: [
            null as CloudEnvironmentDraft | null,
            {
                startNewEnvironment: () => NEW_ENVIRONMENT,
                editEnvironment: (_, { environment }) => draftFromEnvironment(environment),
                updateDraft: (draft, { changes }) => (draft ? { ...draft, ...changes } : draft),
                closeDraft: () => null,
            },
        ],
        draftSaving: [
            false,
            {
                saveDraft: () => true,
                saveDraftDone: () => false,
                closeDraft: () => false,
            },
        ],
        environmentsFailed: [
            false,
            {
                loadEnvironments: () => false,
                loadEnvironmentsSuccess: () => false,
                loadEnvironmentsFailure: () => true,
            },
        ],
    }),
    selectors({
        draftError: [
            (s) => [s.draft],
            (draft: CloudEnvironmentDraft | null): string | null => {
                if (!draft) {
                    return null
                }
                if (!draft.name.trim()) {
                    return 'Enter a name'
                }
                if (
                    draft.network_access_level === SandboxEnvironmentNetworkAccessLevelEnumApi.Custom &&
                    draft.allowed_domains.length === 0 &&
                    !draft.include_default_domains
                ) {
                    return 'Add at least one allowed domain'
                }
                return null
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        saveDraft: async () => {
            const { draft, currentProjectId } = values
            if (!draft || currentProjectId == null || values.draftError) {
                actions.saveDraftDone()
                return
            }
            const body = {
                name: draft.name.trim(),
                network_access_level: draft.network_access_level,
                allowed_domains: draft.allowed_domains,
                include_default_domains: draft.include_default_domains,
                repositories: draft.repositories,
                private: draft.private,
                custom_image_id: draft.custom_image_id,
            }
            try {
                if (draft.id) {
                    await sandboxPartialUpdate(String(currentProjectId), draft.id, body)
                } else {
                    await sandboxCreate(String(currentProjectId), body)
                }
                lemonToast.success(draft.id ? 'Environment saved' : 'Environment created')
                actions.closeDraft()
                actions.loadEnvironments()
            } catch (error: any) {
                lemonToast.error(error?.detail ?? 'The environment did not save. Try again.')
                actions.saveDraftDone()
            }
        },
        deleteEnvironment: async ({ environment }) => {
            if (values.currentProjectId == null) {
                return
            }
            try {
                await sandboxDestroy(String(values.currentProjectId), environment.id)
                lemonToast.success('Environment deleted')
                actions.loadEnvironments()
            } catch {
                lemonToast.error('The environment was not deleted. Try again.')
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadEnvironments()
    }),
])
