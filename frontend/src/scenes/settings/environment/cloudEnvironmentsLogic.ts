import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { projectLogic } from 'scenes/projectLogic'

import { sandboxCreate, sandboxDestroy, sandboxList, sandboxPartialUpdate } from 'products/tasks/frontend/generated/api'
import {
    type SandboxEnvironmentDTOApi,
    SandboxEnvironmentNetworkAccessLevelEnumApi,
} from 'products/tasks/frontend/generated/api.schemas'

export interface CloudEnvironmentDraft {
    id: string | null
    name: string
    network_access_level: SandboxEnvironmentNetworkAccessLevelEnumApi
    allowed_domains: string[]
    include_default_domains: boolean
    repositories: string[]
    private: boolean
    custom_image_id: string | null
}

const NEW_ENVIRONMENT: CloudEnvironmentDraft = {
    id: null,
    name: '',
    network_access_level: SandboxEnvironmentNetworkAccessLevelEnumApi.Trusted,
    allowed_domains: [],
    include_default_domains: true,
    repositories: [],
    private: true,
    custom_image_id: null,
}

function isNetworkAccessLevel(value: string): value is SandboxEnvironmentNetworkAccessLevelEnumApi {
    return (Object.values(SandboxEnvironmentNetworkAccessLevelEnumApi) as string[]).includes(value)
}

export function draftFromEnvironment(environment: SandboxEnvironmentDTOApi): CloudEnvironmentDraft {
    return {
        id: environment.id,
        name: environment.name,
        network_access_level: isNetworkAccessLevel(environment.network_access_level)
            ? environment.network_access_level
            : SandboxEnvironmentNetworkAccessLevelEnumApi.Full,
        allowed_domains: environment.allowed_domains ?? [],
        include_default_domains: environment.include_default_domains,
        repositories: environment.repositories ?? [],
        private: environment.private,
        custom_image_id: environment.custom_image_id ?? null,
    }
}

