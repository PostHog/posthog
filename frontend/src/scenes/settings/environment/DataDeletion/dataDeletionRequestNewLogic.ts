export const dataDeletionRequestNewLogic = kea<dataDeletionRequestNewLogicType>([
    path(['scenes', 'settings', 'environment', 'DataDeletion', 'dataDeletionRequestNewLogic']),

    connect(() => ({
        values: [projectLogic, ['currentProjectId'], sqlEditorLogic(EDITOR_LOGIC_PROPS), ['queryInput']],
        actions: [sqlEditorLogic(EDITOR_LOGIC_PROPS), ['setQueryInput', 'setSourceQuery']],
    })),

    actions({
        setSubmissionId: (submissionId: string) => ({ submissionId }),
        setConfirmationText: (confirmationText: string) => ({ confirmationText }),
    }),

    loaders(({ values }) => ({
        preview: [
            null as DataDeletionPreview | null,
            {
                previewQuery: async () => {
                    const query = values.queryInput ?? ''
                    const { count } = await dataDeletionRequestsPreviewCreate(String(values.currentProjectId), {
                        query,
                    })
                    return { query, count }
                },
                clearPreview: () => null,
            },
        ],
        createdRequest: [
            null as DataDeletionRequestApi | null,
            {
                submitRequest: async () => {
                    if (!values.currentPreview || !values.submissionId) {
                        return null
                    }
                    // Submit the previewed query, so the request deletes exactly what the person confirmed.
                    return await dataDeletionRequestsCreate(String(values.currentProjectId), {
                        query: values.currentPreview.query,
                        submission_id: values.submissionId,
                    })
                },
            },
        ],
    })),

    reducers({
        submissionId: [
            null as string | null,
            {
                setSubmissionId: (_, { submissionId }) => submissionId,
            },
        ],
        confirmationText: [
            '',
            {
                setConfirmationText: (_, { confirmationText }) => confirmationText,
                clearPreview: () => '',
            },
        ],
        previewError: [
            null as string | null,
            {
                previewQuery: () => null,
                clearPreview: () => null,
                previewQueryFailure: (_, { errorObject }) =>
                    errorMessage(errorObject, 'Could not check this query. Check the query and try again.'),
            },
        ],
        submitError: [
            null as string | null,
            {
                submitRequest: () => null,
                clearPreview: () => null,
                submitRequestFailure: (_, { errorObject }) =>
                    errorMessage(errorObject, 'Could not submit the deletion request. Try again.'),
            },
        ],
    }),

    selectors({
        // A preview that finished after the query changed describes a different query, so it does not count.
        currentPreview: [
            (s) => [s.preview, s.queryInput],
            (preview: DataDeletionPreview | null, queryInput: string | null): DataDeletionPreview | null =>
                preview && preview.query === queryInput ? preview : null,
        ],
        queryIsEmpty: [(s) => [s.queryInput], (queryInput: string | null): boolean => !queryInput?.trim()],
        confirmationMatches: [
            (s) => [s.confirmationText],
            (confirmationText: string): boolean => confirmationText.trim().toLowerCase() === DELETION_CONFIRMATION_TEXT,
        ],
        submitDisabledReason: [
            (s) => [s.currentPreview, s.confirmationMatches],
            (preview: DataDeletionPreview | null, confirmationMatches: boolean): string | null => {
                if (!preview) {
                    return 'Check matching events first'
                }
                if (preview.count === 0) {
                    return 'This query matches no events'
                }
                if (!confirmationMatches) {
                    return `Type "${DELETION_CONFIRMATION_TEXT}" to confirm`
                }
                return null
            },
        ],
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: Scene.Settings,
                    name: 'Settings - Data deletion',
                    path: urls.settings('environment-data-deletion'),
                    iconType: 'settings',
                },
                {
                    key: Scene.DataDeletionRequestNew,
                    name: 'New deletion request',
                },
            ],
        ],
    }),

    listeners(({ actions, values }) => ({
        setQueryInput: ({ queryInput }) => {
            if (values.preview && queryInput !== values.preview.query) {
                actions.clearPreview()
            }
        },
        previewQuerySuccess: ({ preview }) => {
            // pinned: analytics event name and properties, renaming breaks dashboards
            posthog.capture('data deletion request previewed', { matched_count: preview?.count ?? null })
        },
        previewQueryFailure: () => {
            posthog.capture('data deletion request preview failed')
        },
        submitRequestSuccess: ({ createdRequest }) => {
            if (!createdRequest) {
                return
            }
            // pinned: analytics event name and properties, renaming breaks dashboards
            posthog.capture('data deletion request submitted', { matched_count: values.currentPreview?.count ?? null })
            lemonToast.success('Deletion request submitted. PostHog reviews it before any events are deleted.')
            router.actions.push(urls.settings('environment-data-deletion'))
        },
    })),

    afterMount(({ actions, values }) => {
        actions.setSubmissionId(uuid())
        if (values.queryInput !== null) {
            return
        }
        actions.setQueryInput(DEFAULT_QUERY)
        actions.setSourceQuery({
            kind: NodeKind.DataVisualizationNode,
            source: { kind: NodeKind.HogQLQuery, query: DEFAULT_QUERY },
            display: ChartDisplayType.ActionsTable,
        })
    }),
])
