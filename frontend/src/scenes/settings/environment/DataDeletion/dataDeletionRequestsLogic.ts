import { MakeLogicType, connect, events, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { projectLogic } from 'scenes/projectLogic'

import { dataDeletionRequestsList } from '~/generated/core/api'
import { type DataDeletionRequestApi, RequestStatusEnumApi } from '~/generated/core/api.schemas'

// Matches MAX_ACTIVE_REQUESTS_PER_TEAM in posthog/data_deletion.py, which rejects the next request with a 409.
export const MAX_ACTIVE_DELETION_REQUESTS = 5

const ACTIVE_STATUSES: ReadonlySet<RequestStatusEnumApi> = new Set([
    RequestStatusEnumApi.Pending,
    RequestStatusEnumApi.Approved,
    RequestStatusEnumApi.InProgress,
    RequestStatusEnumApi.Queued,
])

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataDeletionRequestsLogicValues {
    currentProjectId: number | null // projectLogic
    activeRequestCount: number
    dataDeletionRequests: DataDeletionRequestApi[] | null
    dataDeletionRequestsLoading: boolean
    loadFailed: boolean
    newRequestDisabledReason: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataDeletionRequestsLogicActions {
    loadDataDeletionRequests: () => any
    loadDataDeletionRequestsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadDataDeletionRequestsSuccess: (
        dataDeletionRequests: DataDeletionRequestApi[],
        payload?: any
    ) => {
        dataDeletionRequests: DataDeletionRequestApi[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataDeletionRequestsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        activeRequestCount: (dataDeletionRequests: any) => number
        newRequestDisabledReason: (dataDeletionRequests: any, activeRequestCount: any) => string | null
    }
}

export type dataDeletionRequestsLogicType = MakeLogicType<
    dataDeletionRequestsLogicValues,
    dataDeletionRequestsLogicActions,
    Record<string, any>,
    dataDeletionRequestsLogicMeta
>

export const dataDeletionRequestsLogic = kea<dataDeletionRequestsLogicType>([
    path(['scenes', 'settings', 'environment', 'DataDeletion', 'dataDeletionRequestsLogic']),

    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),

    loaders(({ values }) => ({
        dataDeletionRequests: [
            null as DataDeletionRequestApi[] | null,
            {
                loadDataDeletionRequests: async () => {
                    const response = await dataDeletionRequestsList(String(values.currentProjectId), { limit: 100 })
                    return [...response.results].sort((a, b) => b.created_at.localeCompare(a.created_at))
                },
            },
        ],
    })),

    reducers({
        loadFailed: [
            false,
            {
                loadDataDeletionRequests: () => false,
                loadDataDeletionRequestsFailure: () => true,
            },
        ],
    }),

    selectors({
        activeRequestCount: [
            (s) => [s.dataDeletionRequests],
            (requests: DataDeletionRequestApi[] | null): number =>
                requests?.filter((request) => ACTIVE_STATUSES.has(request.status)).length ?? 0,
        ],
        newRequestDisabledReason: [
            (s) => [s.dataDeletionRequests, s.activeRequestCount],
            (requests: DataDeletionRequestApi[] | null, activeRequestCount: number): string | null => {
                if (requests === null) {
                    return 'Loading deletion requests'
                }
                if (activeRequestCount >= MAX_ACTIVE_DELETION_REQUESTS) {
                    return `This project already has ${MAX_ACTIVE_DELETION_REQUESTS} active deletion requests. Submit a new one after one of them completes.`
                }
                return null
            },
        ],
    }),

    events(({ actions }) => ({
        afterMount: () => actions.loadDataDeletionRequests(),
    })),
])
