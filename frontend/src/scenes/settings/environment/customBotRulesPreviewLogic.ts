import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    getContext,
    kea,
    key,
    listeners,
    path,
    props,
    propsChanged,
    reducers,
} from 'kea'

import { DisposablesManager } from '~/kea-disposables'
import { CustomBotField, CustomBotRule } from '~/queries/schema/schema-general'

import { CustomBotPreviewResult, startCustomBotRulesPreview } from './customBotRulesUtils'

export interface CustomBotRulesPreviewProps {
    instanceKey: string
    rules: CustomBotRule[]
    testValues: Partial<Record<CustomBotField, string>>
}

type Preview = { status: 'idle' } | { status: 'pending' } | CustomBotPreviewResult

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customBotRulesPreviewLogicValues {
    preview: Preview
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customBotRulesPreviewLogicActions {
    refresh: () => {
        value: true
    }
    setPreview: (preview: Preview) => {
        preview: Preview
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface customBotRulesPreviewLogicMeta {
    key: string
}

export type customBotRulesPreviewLogicType = MakeLogicType<
    customBotRulesPreviewLogicValues,
    customBotRulesPreviewLogicActions,
    CustomBotRulesPreviewProps,
    customBotRulesPreviewLogicMeta
>

export const customBotRulesPreviewLogic: LogicWrapper<customBotRulesPreviewLogicType> =
    kea<customBotRulesPreviewLogicType>([
        props({} as CustomBotRulesPreviewProps),
        key((props) => props.instanceKey),
        path((key) => ['scenes', 'settings', 'environment', 'customBotRulesPreviewLogic', key]),
        actions({ refresh: true, setPreview: (preview: Preview) => ({ preview }) }),
        reducers({ preview: [{ status: 'idle' } as Preview, { setPreview: (_, { preview }) => preview }] }),
        listeners(({ actions, props, cache }) => ({
            refresh: () => {
                const fingerprint = JSON.stringify([props.rules, props.testValues])
                if (cache.fingerprint === fingerprint) {
                    return
                }
                cache.fingerprint = fingerprint
                const manager: DisposablesManager = cache.disposables
                manager.dispose('preview')
                if (!props.rules.some((rule) => rule.items.some((item) => props.testValues[item.key]?.trim()))) {
                    actions.setPreview({ status: 'idle' })
                    return
                }
                actions.setPreview({ status: 'pending' })
                const context = getContext()
                manager.add(
                    () => {
                        let active = true
                        const request = startCustomBotRulesPreview(props.rules, props.testValues)
                        void request.promise.then((result) => {
                            if (!active || manager.isDisposed || getContext() !== context) {
                                return
                            }
                            manager.dispose('preview')
                            actions.setPreview(result)
                        })
                        return () => {
                            active = false
                            request.cancel()
                        }
                    },
                    'preview',
                    { pauseOnPageHidden: false }
                )
            },
        })),
        afterMount(({ actions, cache }) => {
            cache.fingerprint = undefined
            actions.refresh()
        }),
        propsChanged(({ actions }) => {
            actions.refresh()
        }),
    ])
