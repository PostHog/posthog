function isSubscribedOnServer(
    members: PipelineNotificationMemberApi[] | null,
    userId: number,
    pipelineId: string
): boolean {
    const member = (members ?? []).find((candidate) => candidate.user_id === userId)
    return !member?.unsubscribed_pipeline_ids.includes(pipelineId)
}

export const pipelineNotificationAdminLogic = kea<pipelineNotificationAdminLogicType>([
    path(['scenes', 'settings', 'environment', 'pipelineNotificationAdminLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
    })),
    actions({
        setSubscription: (userId: number, pipelineId: string, subscribed: boolean) => ({
            userId,
            pipelineId,
            subscribed,
        }),
        setSubscriptionForAllMembers: (pipelineId: string, subscribed: boolean) => ({ pipelineId, subscribed }),
        discardChanges: true,
        saveChanges: true,
        saveChangesSuccess: true,
        saveChangesFailure: true,
    }),
    loaders(({ values }) => ({
        // Null means the list has not answered yet, so the section can tell "still loading" apart
        // from "this project has no pipelines".
        members: [
            null as PipelineNotificationMemberApi[] | null,
            {
                loadMembers: async () => {
                    if (!values.currentTeam) {
                        return []
                    }
                    return await pipelineNotificationSubscriptionsList(String(values.currentTeam.id))
                },
            },
        ],
        pipelines: [
            null as PipelineItem[] | null,
            {
                loadPipelines: async () => {
                    if (!values.currentTeam) {
                        return []
                    }
                    return await loadTeamPipelines(values.currentTeam)
                },
            },
        ],
    })),
    reducers({
        pendingChanges: [
            {} as PendingChanges,
            {
                setSubscription: (state, { userId, pipelineId, subscribed }) => ({
                    ...state,
                    [changeKey(userId, pipelineId)]: subscribed,
                }),
                discardChanges: () => ({}),
                saveChangesSuccess: () => ({}),
            },
        ],
        savingChanges: [
            false,
            {
                saveChanges: () => true,
                saveChangesSuccess: () => false,
                saveChangesFailure: () => false,
            },
        ],
    }),
    selectors({
        // Intent is stored raw, so a member toggled back to the value they already have drops out
        // here rather than being sent as a no-op change.
        changesToSave: [
            (s) => [s.pendingChanges, s.members],
            (
                pendingChanges: PendingChanges,
                members: PipelineNotificationMemberApi[] | null
            ): PipelineNotificationChangeApi[] =>
                Object.entries(pendingChanges)
                    .map(([key, subscribed]) => {
                        const [userId, pipelineId] = [Number(key.split(':')[0]), key.slice(key.indexOf(':') + 1)]
                        return { user_id: userId, pipeline_id: pipelineId, subscribed }
                    })
                    .filter(
                        ({ user_id, pipeline_id, subscribed }) =>
                            subscribed !== isSubscribedOnServer(members, user_id, pipeline_id)
                    ),
        ],
        pendingChangeCount: [
            (s) => [s.changesToSave],
            (changesToSave: PipelineNotificationChangeApi[]): number => changesToSave.length,
        ],
        affectedMemberCount: [
            (s) => [s.changesToSave],
            (changesToSave: PipelineNotificationChangeApi[]): number =>
                new Set(changesToSave.map((change) => change.user_id)).size,
        ],
        isSubscribed: [
            (s) => [s.pendingChanges, s.members],
            (pendingChanges: PendingChanges, members: PipelineNotificationMemberApi[] | null) =>
                (userId: number, pipelineId: string): boolean => {
                    const pending = pendingChanges[changeKey(userId, pipelineId)]
                    return pending ?? isSubscribedOnServer(members, userId, pipelineId)
                },
        ],
    }),
    listeners(({ actions, values }) => ({
        setSubscriptionForAllMembers: ({ pipelineId, subscribed }) => {
            for (const member of values.members ?? []) {
                if (member.editable) {
                    actions.setSubscription(member.user_id, pipelineId, subscribed)
                }
            }
        },
        saveChanges: async () => {
            const changes = values.changesToSave
            if (!changes.length || !values.currentTeam) {
                actions.saveChangesSuccess()
                return
            }
            try {
                await pipelineNotificationSubscriptionsBulkUpdateCreate(String(values.currentTeam.id), { changes })
            } catch (error) {
                actions.saveChangesFailure()
                lemonToast.error("Couldn't save the changes. Try again, and if it keeps happening contact support.")
                throw error
            }
            actions.saveChangesSuccess()
            actions.loadMembers()
            lemonToast.success('Notification settings saved')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadMembers()
        actions.loadPipelines()
    }),
])
