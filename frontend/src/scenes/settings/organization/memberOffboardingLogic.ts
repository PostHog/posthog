export const memberOffboardingLogic = kea<memberOffboardingLogicType>([
    path(['scenes', 'settings', 'organization', 'memberOffboardingLogic']),
    connect({
        values: [organizationLogic, ['currentOrganization'], userLogic, ['user']],
        actions: [membersLogic, ['loadMemberScopedApiKeys', 'postRemoveMember']],
    }),
    actions({
        open: (member: OrganizationMemberType) => ({ member }),
        close: true,
        setKeep: (id: string, keep: boolean) => ({ id, keep }),
        disableResources: (ids: string[]) => ({ ids }),
        setKeptResources: (ids: string[]) => ({ ids }),
        loadResources: true,
        remove: true,
    }),
    reducers({
        member: [null as OrganizationMemberType | null, { open: (_, { member }) => member, close: () => null }],
        keep: [
            [] as string[],
            {
                open: () => [],
                setKeptResources: (_, { ids }) => ids,
            },
        ],
        loadError: [
            null as string | null,
            { open: () => null, loadResources: () => null, loadResourcesFailure: (_, { error }) => error },
        ],
    }),
    loaders(({ values, actions }) => ({
        resources: {
            __default: null as MemberOffboardingResourceApi[] | null,
            loadResources: async (_, breakpoint) => {
                const member = values.member
                if (!member) {
                    return null
                }
                const resources = await membersOffboardingRetrieve(
                    values.currentOrganization?.id ?? '@current',
                    member.user.uuid
                )
                breakpoint()
                return resources
            },
        },
        savingResources: {
            __default: false,
            saveResources: async ({ ids, enabled }: { ids: string[]; enabled: boolean }) => {
                if (!values.member) {
                    return false
                }
                const selected = (values.resources ?? []).filter((resource) => ids.includes(resource.id))
                const results = await Promise.allSettled(
                    selected.map(async (resource) => {
                        const projectId = String(resource.team_id)
                        const resourceId = resource.resource_id
                        if (resource.kind === 'subscription') {
                            await subscriptionsPartialUpdate(projectId, Number(resourceId), { enabled })
                            return resource.id
                        }
                        if (resource.kind === 'alert') {
                            await alertsPartialUpdate(projectId, resourceId, { enabled })
                            return resource.id
                        }
                        const url =
                            resource.kind === 'dashboard'
                                ? getDashboardsSharingListUrl(projectId, Number(resourceId))
                                : resource.kind === 'insight'
                                  ? getInsightsSharingListUrl(projectId, Number(resourceId))
                                  : resource.kind === 'notebook'
                                    ? getNotebooksSharingListUrl(projectId, resourceId)
                                    : getSessionRecordingsSharingListUrl(projectId, resourceId)
                        // Sharing PATCH is supported by the API but not exposed by its generated client yet.
                        await api.update(url, { enabled })
                        return resource.id
                    })
                )
                const savedIds = results.flatMap((result) => (result.status === 'fulfilled' ? [result.value] : []))
                actions.setKeptResources(
                    enabled
                        ? [...new Set([...values.keep, ...savedIds])]
                        : values.keep.filter((id) => !savedIds.includes(id))
                )
                const failed = selected.filter((_, index) => results[index].status === 'rejected')
                if (failed.length) {
                    lemonToast.error(
                        `Couldn't update ${failed.map((resource) => resource.name).join(', ')}. Please try again.`
                    )
                }
                return true
            },
        },
        removed: {
            __default: false,
            remove: async () => {
                if (
                    !values.member ||
                    values.resourcesLoading ||
                    values.savingResourcesLoading ||
                    values.loadError ||
                    values.resources === null
                ) {
                    return false
                }
                const member = values.member
                await membersOffboardCreate(values.currentOrganization?.id ?? '@current', member.user.uuid)
                lemonToast.success(`Removed ${fullNameOrEmail(member.user)} from organization`)
                actions.close()
                actions.postRemoveMember(member.user.uuid)
                return true
            },
        },
    })),
    selectors({
        publicResources: [
            (s) => [s.resources],
            (resources: MemberOffboardingResourceApi[] | null): MemberOffboardingResourceApi[] =>
                (resources ?? []).filter((resource) => resource.kind !== 'subscription' && resource.kind !== 'alert'),
        ],
        subscriptions: [
            (s) => [s.resources],
            (resources: MemberOffboardingResourceApi[] | null): MemberOffboardingResourceApi[] =>
                (resources ?? []).filter((resource) => resource.kind === 'subscription' || resource.kind === 'alert'),
        ],
        getSelectionLabel: [
            (s) => [s.resources],
            (resources: MemberOffboardingResourceApi[] | null) =>
                (selectedKeys: ReadonlyArray<string>): string => {
                    const selected = new Set(selectedKeys)
                    const counts = new Map<string, number>()
                    for (const resource of resources ?? []) {
                        if (selected.has(resource.id)) {
                            counts.set(resource.kind, (counts.get(resource.kind) ?? 0) + 1)
                        }
                    }
                    const labels = ['dashboard', 'insight', 'notebook', 'recording', 'subscription', 'alert']
                        .filter((kind) => counts.has(kind))
                        .map((kind) => pluralize(counts.get(kind)!, kind))
                    return labels.join(', ')
                },
        ],
    }),
    listeners(({ actions, values }) => ({
        setKeep: ({ id, keep }) => {
            if (!values.savingResourcesLoading && !values.removedLoading) {
                actions.saveResources({ ids: [id], enabled: keep })
            }
        },
        disableResources: ({ ids }) => {
            if (!values.savingResourcesLoading && !values.removedLoading && ids.length > 0) {
                actions.saveResources({ ids, enabled: false })
            }
        },
        saveResourcesFailure: () => {
            lemonToast.error("Couldn't save changes. Please try again.")
        },
        loadResourcesSuccess: ({ resources }) => {
            actions.setKeptResources(
                values.member?.user.uuid === values.user?.uuid ? [] : (resources ?? []).map((resource) => resource.id)
            )
        },
        open: ({ member }) => {
            actions.loadMemberScopedApiKeys(member)
            actions.loadResources()
        },
    })),
])
