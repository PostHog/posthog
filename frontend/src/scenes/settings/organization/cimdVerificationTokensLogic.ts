/**
 * Cheap client-side check for the two most common mistakes (missing HTTPS, missing path)
 * so the user doesn't need a round trip to find out. The server is still the source of
 * truth for every other rejection reason (query string, port, etc).
 */
export function validateCimdUrl(url: string): string | null {
    if (!url) {
        return 'Please enter your CIMD metadata URL'
    }
    if (!url.startsWith('https://')) {
        return 'The metadata URL must start with https://'
    }
    let parsed: URL
    try {
        parsed = new URL(url)
    } catch {
        return 'Please enter a valid URL'
    }
    if (parsed.pathname === '/' || parsed.pathname === '') {
        return 'The metadata URL must include a path, e.g. /.well-known/oauth-client-metadata.json'
    }
    return null
}

function extractServerError(e: any, fallback: string): string {
    return e?.detail ?? e?.cimd_url?.[0] ?? e?.label?.[0] ?? fallback
}

