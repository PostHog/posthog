export const cimdVerificationTokensLogic = kea<cimdVerificationTokensLogicType>([
    path(['scenes', 'settings', 'organization', 'cimdVerificationTokensLogic']),

    actions({
        showCreateDialog: true,
        hideCreateDialog: true,
        setNewTokenLabel: (label: string) => ({ label }),
        setNewTokenUrl: (url: string) => ({ url }),
        setIsCreatingToken: (creating: boolean) => ({ creating }),
        setJustCreatedToken: (token: CIMDVerificationTokenWithValue | null) => ({ token }),
        createToken: true,
        deleteToken: (token: CIMDVerificationToken) => ({ token }),
        showBindDialog: (token: CIMDVerificationToken) => ({ token }),
        hideBindDialog: true,
        setBindUrl: (url: string) => ({ url }),
        setIsBindingToken: (binding: boolean) => ({ binding }),
        bindToken: true,
    }),

    reducers({
        isCreateDialogOpen: [
            false,
            {
                showCreateDialog: () => true,
                hideCreateDialog: () => false,
            },
        ],
        isCreatingToken: [
            false,
            {
                setIsCreatingToken: (_, { creating }) => creating,
            },
        ],
        newTokenLabel: [
            '',
            {
                setNewTokenLabel: (_, { label }) => label,
                hideCreateDialog: () => '',
            },
        ],
        newTokenUrl: [
            '',
            {
                setNewTokenUrl: (_, { url }) => url,
                hideCreateDialog: () => '',
            },
        ],
        justCreatedToken: [
            null as CIMDVerificationTokenWithValue | null,
            {
                setJustCreatedToken: (_, { token }) => token,
            },
        ],
        bindingToken: [
            null as CIMDVerificationToken | null,
            {
                showBindDialog: (_, { token }) => token,
                hideBindDialog: () => null,
            },
        ],
        bindUrl: [
            '',
            {
                setBindUrl: (_, { url }) => url,
                showBindDialog: () => '',
                hideBindDialog: () => '',
            },
        ],
        isBindingToken: [
            false,
            {
                setIsBindingToken: (_, { binding }) => binding,
            },
        ],
    }),

    loaders({
        tokens: [
            [] as CIMDVerificationToken[],
            {
                loadTokens: async () => {
                    const orgId = organizationLogic.values.currentOrganization?.id
                    if (!orgId) {
                        return []
                    }
                    const response = await cimdVerificationTokensList(orgId)
                    return response.results
                },
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        createToken: async () => {
            const orgId = organizationLogic.values.currentOrganization?.id
            if (!orgId) {
                return
            }
            const label = values.newTokenLabel.trim()
            if (!label) {
                lemonToast.error('Please enter a label for this token.')
                return
            }
            const cimdUrl = values.newTokenUrl.trim()
            const urlError = validateCimdUrl(cimdUrl)
            if (urlError) {
                lemonToast.error(urlError)
                return
            }
            actions.setIsCreatingToken(true)
            try {
                const created = await cimdVerificationTokensCreate(orgId, { label, cimd_url: cimdUrl })
                actions.setJustCreatedToken(created)
                actions.hideCreateDialog()
                actions.loadTokens()
            } catch (e: any) {
                lemonToast.error(extractServerError(e, 'Failed to create token'))
            } finally {
                actions.setIsCreatingToken(false)
            }
        },
        deleteToken: async ({ token }) => {
            const orgId = organizationLogic.values.currentOrganization?.id
            if (!orgId) {
                return
            }
            try {
                await cimdVerificationTokensDestroy(orgId, token.id)
                lemonToast.success('Token revoked')
                actions.loadTokens()
            } catch (e: any) {
                lemonToast.error(extractServerError(e, 'Failed to revoke token'))
            }
        },
        bindToken: async () => {
            const orgId = organizationLogic.values.currentOrganization?.id
            const token = values.bindingToken
            if (!orgId || !token) {
                return
            }
            const cimdUrl = values.bindUrl.trim()
            const urlError = validateCimdUrl(cimdUrl)
            if (urlError) {
                lemonToast.error(urlError)
                return
            }
            actions.setIsBindingToken(true)
            try {
                await cimdVerificationTokensPartialUpdate(orgId, token.id, { cimd_url: cimdUrl })
                lemonToast.success('Metadata URL set. The token will verify there now.')
                actions.hideBindDialog()
                actions.loadTokens()
            } catch (e: any) {
                lemonToast.error(extractServerError(e, 'Failed to set metadata URL'))
            } finally {
                actions.setIsBindingToken(false)
            }
        },
    })),

    afterMount(({ actions }) => {
        actions.loadTokens()
    }),
])
