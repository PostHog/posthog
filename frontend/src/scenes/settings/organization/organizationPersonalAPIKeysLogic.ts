import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api, { ApiConfig, ApiError } from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { capitalizeFirstLetter, fullName, pluralize } from 'lib/utils/strings'

import {
    getPersonalApiKeysListUrl,
    organizationPersonalApiKeysRevoke,
    organizationPersonalApiKeysRoll,
} from 'products/platform_features/frontend/generated/api'
import type {
    OrganizationPersonalAPIKeyActionResultApi,
    OrganizationPersonalAPIKeyApi,
} from 'products/platform_features/frontend/generated/api.schemas'

export type KeyAction = 'roll' | 'revoke'
export type KeyActionTarget = 'single'

interface KeyActionCounts {
    rolled: number
    deleted: number
}

function countsFromOutcome({ outcome }: OrganizationPersonalAPIKeyActionResultApi): KeyActionCounts {
    return {
        rolled: outcome === 'rolled' ? 1 : 0,
        deleted: outcome === 'deleted' ? 1 : 0,
    }
}

function describeCounts({ rolled, deleted }: KeyActionCounts): string {
    const parts = [
        rolled ? `rolled ${pluralize(rolled, 'key')}` : null,
        deleted ? `revoked ${pluralize(deleted, 'key')}` : null,
    ].filter((part): part is string => part !== null)
    return parts.length ? capitalizeFirstLetter(parts.join(', ')) : 'No keys changed'
}

function describeFailure(action: KeyAction, target: KeyActionTarget, error: unknown): string {
    const status = error instanceof ApiError ? error.status : undefined
    if (target === 'single' && status === 404) {
        return `Couldn't ${action} this key. It may have been deleted or no longer have access to this organization.`
    }
    const detail = error instanceof ApiError ? error.detail : null
    return `Couldn't ${action} this key. ${detail || 'Please try again.'}`
}

