export interface organizationPersonalAPIKeysLogicValues {
    isAdminOrOwner: boolean | null // organizationLogic
    hasAvailableFeature: (feature: AvailableFeature, currentUsage?: number | undefined) => boolean // userLogic
    canLoadKeys: boolean
    filteredKeys: OrganizationPersonalAPIKeyApi[]
    keys: OrganizationPersonalAPIKeyApi[]
    keysLoading: boolean
    keysRequested: boolean
    search: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface organizationPersonalAPIKeysLogicActions {
    loadKeys: () => any
    loadKeysFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadKeysSuccess: (
        keys: OrganizationPersonalAPIKeyApi[],
        payload?: any
    ) => {
        keys: OrganizationPersonalAPIKeyApi[]
        payload?: any
    }
    setSearch: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface organizationPersonalAPIKeysLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        canLoadKeys: (
            isAdminOrOwner: boolean | null,
            hasAvailableFeature: (feature: AvailableFeature, currentUsage?: number | undefined) => boolean
        ) => boolean
        filteredKeys: (keys: OrganizationPersonalAPIKeyApi[], search: string) => OrganizationPersonalAPIKeyApi[]
    }
}

export type organizationPersonalAPIKeysLogicType = MakeLogicType<
    organizationPersonalAPIKeysLogicValues,
    organizationPersonalAPIKeysLogicActions,
    Record<string, any>,
    organizationPersonalAPIKeysLogicMeta
>

export const organizationPersonalAPIKeysLogic = kea<organizationPersonalAPIKeysLogicType>([
    path(['scenes', 'settings', 'organization', 'organizationPersonalAPIKeysLogic']),
    connect(() => ({
        values: [organizationLogic, ['isAdminOrOwner'], userLogic, ['hasAvailableFeature']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
    }),
    loaders({
        keys: [
            [] as OrganizationPersonalAPIKeyApi[],
            {
                loadKeys: async () => {
                    // Page through everything — an incomplete list would be a security-audit blind spot.
                    const url = getPersonalApiKeysListUrl(ApiConfig.getCurrentOrganizationId())
                    return await api.loadPaginatedResults<OrganizationPersonalAPIKeyApi>(url)
                },
            },
        ],
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        // Guards against firing loadKeys twice — once from afterMount and once from the
        // subscription that waits for the org/user to finish loading.
        keysRequested: [false, { loadKeys: () => true }],
    }),
    selectors({
        // The backend gates this endpoint on admin/owner access plus the security-settings
        // entitlement. Match those conditions so an unentitled org or a plain member never fires
        // a call that can only fail — a 402 would otherwise leak the raw upsell string into a red
        // error toast sitting right next to the paygate.
        canLoadKeys: [
            (s) => [s.isAdminOrOwner, s.hasAvailableFeature],
            (
                isAdminOrOwner: boolean | null,
                hasAvailableFeature: (feature: AvailableFeature, currentUsage?: number | undefined) => boolean
            ): boolean => !!isAdminOrOwner && hasAvailableFeature(AvailableFeature.ORGANIZATION_SECURITY_SETTINGS),
        ],
        // Client-side filtering — the full list is already loaded, so this stays in the browser.
        filteredKeys: [
            (s) => [s.keys, s.search],
            (keys: OrganizationPersonalAPIKeyApi[], search: string): OrganizationPersonalAPIKeyApi[] => {
                const term = search.trim().toLowerCase()
                if (!term) {
                    return keys
                }
                return keys.filter((key) =>
                    [fullName(key.owner), key.owner.email, ...key.scopes].some((field) =>
                        field.toLowerCase().includes(term)
                    )
                )
            },
        ],
    }),
    subscriptions(({ actions, values }) => ({
        // The logic mounts before the org/user have loaded, so the gate can open after mount.
        // Fire the load the moment it does, unless afterMount already did.
        canLoadKeys: (canLoadKeys: boolean) => {
            if (canLoadKeys && !values.keysRequested) {
                actions.loadKeys()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.canLoadKeys && !values.keysRequested) {
            actions.loadKeys()
        }
    }),
])
