export const organizationPersonalAPIKeysLogic = kea<organizationPersonalAPIKeysLogicType>([
    path(['scenes', 'settings', 'organization', 'organizationPersonalAPIKeysLogic']),
    actions({
        setSearch: (search: string) => ({ search }),
        rollKey: (id: string) => ({ id }),
        revokeKey: (id: string) => ({ id }),
        keyActionSuccess: (inFlight: string) => ({ inFlight }),
        keyActionFailure: (inFlight: string) => ({ inFlight }),
    }),
    loaders({
        keys: [
            [] as OrganizationPersonalAPIKeyApi[],
            {
                loadKeys: async () => {
                    // Page through everything — an incomplete list would be a security-audit blind spot.
                    const url = getPersonalApiKeysListUrl(ApiConfig.getCurrentOrganizationId())
                    // nosemgrep: prefer-codegen-api -- Legacy raw API call with a URL built at runtime and an unchecked response type. Use a generated function if one covers this endpoint.
                    return await api.loadPaginatedResults<OrganizationPersonalAPIKeyApi>(url)
                },
            },
        ],
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        // A finished action clears only its own marker, so it does not unmark an action that started after it.
        keyActionInFlight: [
            null as string | null,
            {
                rollKey: (_, { id }) => id,
                revokeKey: (_, { id }) => id,
                keyActionSuccess: (state, { inFlight }) => (state === inFlight ? null : state),
                keyActionFailure: (state, { inFlight }) => (state === inFlight ? null : state),
            },
        ],
    }),
    selectors({
        // Client-side filtering — the full list is already loaded, so this stays in the browser.
        filteredKeys: [
            (s) => [s.keys, s.search],
            (keys: OrganizationPersonalAPIKeyApi[], search: string): OrganizationPersonalAPIKeyApi[] => {
                const term = search.trim().toLowerCase()
                if (!term) {
                    return keys
                }
                return keys.filter((key) =>
                    [fullName(key.owner), key.owner.email, ...key.scopes].some((field) =>
                        field.toLowerCase().includes(term)
                    )
                )
            },
        ],
    }),
    listeners(({ actions, cache }) => {
        const runKeyAction = async (
            action: KeyAction,
            inFlight: string,
            request: (organizationId: string) => Promise<KeyActionCounts>
        ): Promise<void> => {
            const target: KeyActionTarget = 'single'
            posthog.capture('organization personal api key action confirmed', { action, target })
            try {
                const counts = await request(ApiConfig.getCurrentOrganizationId())
                lemonToast.success(describeCounts(counts))
                posthog.capture('organization personal api key action completed', { action, target, ...counts })
                actions.keyActionSuccess(inFlight)
            } catch (error) {
                lemonToast.error(describeFailure(action, target, error))
                posthog.capture('organization personal api key action failed', {
                    action,
                    target,
                    status: error instanceof ApiError ? error.status : undefined,
                })
                actions.keyActionFailure(inFlight)
            }
            // A missing key or a lost response can leave the list stale even when the request fails.
            actions.loadKeys()
        }

        return {
            loadKeysSuccess: ({ keys }) => {
                // Every key action reloads the list, so only the first load counts as a view.
                if (!cache.viewCaptured) {
                    cache.viewCaptured = true
                    posthog.capture('organization personal api keys viewed', { key_count: keys.length })
                }
            },
            rollKey: async ({ id }) => {
                await runKeyAction('roll', id, async (organizationId) =>
                    countsFromOutcome(await organizationPersonalApiKeysRoll(organizationId, id))
                )
            },
            revokeKey: async ({ id }) => {
                await runKeyAction('revoke', id, async (organizationId) =>
                    countsFromOutcome(await organizationPersonalApiKeysRevoke(organizationId, id))
                )
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadKeys()
    }),
])
