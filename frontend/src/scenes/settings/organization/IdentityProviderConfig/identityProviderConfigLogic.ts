export interface IdentityProviderConfigForm {
    domain_scope: DomainScopeEnumApi
    organization_domain_ids: string[]
    saml_entity_id: string
    saml_acs_url: string
    saml_x509_cert: string
    scim_enabled: boolean
    id_jag_issuer_url: string
    id_jag_jwks_url: string
    id_jag_allowed_clients: string[]
}

type IdentityProviderConfigWritePayload = Pick<IdentityProviderConfigApi, 'domain_scope' | 'organization_domain_ids'> &
    Partial<
        Pick<
            IdentityProviderConfigApi,
            | 'config_scope'
            | 'saml_entity_id'
            | 'saml_acs_url'
            | 'saml_x509_cert'
            | 'scim_enabled'
            | 'id_jag_issuer_url'
            | 'id_jag_jwks_url'
            | 'id_jag_allowed_clients'
        >
    >

const NEW_CONFIG_ID = 'new'
const ORGANIZATION_DOMAINS_PAGE_SIZE = 100

const emptyIdentityProviderConfigForm = (): IdentityProviderConfigForm => ({
    domain_scope: DomainScopeEnumApi.All,
    organization_domain_ids: [],
    saml_entity_id: '',
    saml_acs_url: '',
    saml_x509_cert: '',
    scim_enabled: false,
    id_jag_issuer_url: '',
    id_jag_jwks_url: '',
    id_jag_allowed_clients: [],
})

const formValuesFromConfig = (config: IdentityProviderConfigApi | null): IdentityProviderConfigForm => ({
    domain_scope:
        !config || config.domain_scope === DomainScopeEnumApi.All
            ? DomainScopeEnumApi.All
            : DomainScopeEnumApi.Selected,
    organization_domain_ids: config?.organization_domain_ids ?? [],
    saml_entity_id: config?.saml_entity_id ?? '',
    saml_acs_url: config?.saml_acs_url ?? '',
    saml_x509_cert: config?.saml_x509_cert ?? '',
    scim_enabled: config?.scim_enabled ?? false,
    id_jag_issuer_url: config?.id_jag_issuer_url ?? '',
    id_jag_jwks_url: config?.id_jag_jwks_url ?? '',
    id_jag_allowed_clients: config?.id_jag_allowed_clients ?? [],
})

const payloadFromForm = (
    configScope: ConfigScopeEnumApi,
    formValues: IdentityProviderConfigForm
): IdentityProviderConfigWritePayload => {
    const commonPayload = {
        domain_scope: formValues.domain_scope,
        organization_domain_ids:
            formValues.domain_scope === DomainScopeEnumApi.All ? [] : formValues.organization_domain_ids,
    }

    if (configScope === ConfigScopeEnumApi.Saml) {
        return {
            ...commonPayload,
            saml_entity_id: formValues.saml_entity_id.trim() || null,
            saml_acs_url: formValues.saml_acs_url.trim() || null,
            saml_x509_cert: formValues.saml_x509_cert.trim() || null,
        }
    }

    if (configScope === ConfigScopeEnumApi.Scim) {
        return { ...commonPayload, scim_enabled: formValues.scim_enabled }
    }

    return {
        ...commonPayload,
        id_jag_issuer_url: formValues.id_jag_issuer_url.trim() || null,
        id_jag_jwks_url: formValues.id_jag_jwks_url.trim() || null,
        id_jag_allowed_clients: formValues.id_jag_allowed_clients,
    }
}

const isSecureUrl = (value: string): boolean => {
    try {
        return new URL(value).protocol === 'https:'
    } catch {
        return false
    }
}

