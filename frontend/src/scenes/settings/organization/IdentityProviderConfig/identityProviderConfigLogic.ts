export const identityProviderConfigLogic = kea<identityProviderConfigLogicType>([
    props({ configScope: null, configId: NEW_CONFIG_ID } as IdentityProviderConfigLogicProps),
    key((props) => props.configScope ?? 'invalid'),
    path((logicKey) => [
        'scenes',
        'settings',
        'organization',
        'identityProviderConfig',
        'identityProviderConfigLogic',
        logicKey,
    ]),
    connect(() => ({
        values: [
            organizationLogic,
            ['currentOrganizationId'],
            identityProviderConfigsLogic,
            ['identityProviderConfigs'],
            featureFlagLogic,
            ['featureFlags', 'receivedFeatureFlags'],
        ],
        actions: [featureFlagLogic, ['setFeatureFlags']],
    })),
    actions({
        setRevealedScimToken: (token: string | null) => ({ token }),
    }),
    forms(({ actions, props, values }) => ({
        identityProviderConfigForm: {
            defaults: emptyIdentityProviderConfigForm(),
            errors: (formValues) => ({
                organization_domain_ids:
                    formValues.domain_scope === DomainScopeEnumApi.Selected &&
                    formValues.organization_domain_ids.length === 0
                        ? ['Select at least one domain']
                        : undefined,
                saml_acs_url:
                    props.configScope === ConfigScopeEnumApi.Saml &&
                    formValues.saml_acs_url &&
                    !isSecureUrl(formValues.saml_acs_url)
                        ? 'Enter a valid URL that starts with https://'
                        : undefined,
                id_jag_issuer_url:
                    props.configScope === ConfigScopeEnumApi.Xaa &&
                    formValues.id_jag_issuer_url &&
                    !isSecureUrl(formValues.id_jag_issuer_url)
                        ? 'Enter a valid URL that starts with https://'
                        : undefined,
                id_jag_jwks_url:
                    props.configScope === ConfigScopeEnumApi.Xaa &&
                    formValues.id_jag_jwks_url &&
                    !isSecureUrl(formValues.id_jag_jwks_url)
                        ? 'Enter a valid URL that starts with https://'
                        : undefined,
            }),
            submit: async (formValues) => {
                if (!props.configScope) {
                    return
                }

                const payload = payloadFromForm(props.configScope, formValues)
                const config =
                    props.configId === NEW_CONFIG_ID
                        ? await api.identityProviderConfigsCreate(values.currentOrganizationId, {
                              ...payload,
                              config_scope: props.configScope,
                          })
                        : await api.identityProviderConfigsPartialUpdate(
                              values.currentOrganizationId,
                              props.configId,
                              payload
                          )

                actions.loadIdentityProviderConfigSuccess(config)
                actions.setRevealedScimToken(config.scim_bearer_token)
            },
        },
    })),
    loaders(({ props, values }) => ({
        identityProviderConfig: [
            null as IdentityProviderConfigApi | null,
            {
                loadIdentityProviderConfig: async () =>
                    props.configId === NEW_CONFIG_ID
                        ? null
                        : await api.identityProviderConfigsRetrieve(values.currentOrganizationId, props.configId),
            },
        ],
        organizationDomains: [
            null as OrganizationDomainApi[] | null,
            {
                loadOrganizationDomains: async () => {
                    const organizationDomains: OrganizationDomainApi[] = []
                    let offset = 0
                    let next: string | null | undefined

                    do {
                        const page = await api.domainsList(values.currentOrganizationId, {
                            limit: ORGANIZATION_DOMAINS_PAGE_SIZE,
                            offset,
                        })
                        organizationDomains.push(...page.results)
                        offset += ORGANIZATION_DOMAINS_PAGE_SIZE
                        next = page.next
                    } while (next)

                    return organizationDomains
                },
            },
        ],
        regeneratedScimToken: [
            null as string | null,
            {
                regenerateScimToken: async () => {
                    if (!values.identityProviderConfig) {
                        return null
                    }
                    const response = await api.identityProviderConfigsScimTokenCreate(
                        values.currentOrganizationId,
                        values.identityProviderConfig.id
                    )
                    return response.scim_bearer_token
                },
            },
        ],
    })),
    reducers({
        identityProviderConfigLoaded: [
            false,
            {
                loadIdentityProviderConfig: () => false,
                loadIdentityProviderConfigSuccess: () => true,
                loadIdentityProviderConfigFailure: () => true,
            },
        ],
        identityProviderConfigLoadFailed: [
            false,
            {
                loadIdentityProviderConfig: () => false,
                loadIdentityProviderConfigFailure: () => true,
            },
        ],
        organizationDomainsLoadFailed: [
            false,
            {
                loadOrganizationDomains: () => false,
                loadOrganizationDomainsFailure: () => true,
            },
        ],
        revealedScimToken: [
            null as string | null,
            {
                loadIdentityProviderConfig: () => null,
                setRevealedScimToken: (_, { token }) => token,
            },
        ],
    }),
    selectors({
        configScope: [
            (_, props) => [props.configScope],
            (configScope: ConfigScopeEnumApi | null): ConfigScopeEnumApi | null => configScope,
        ],
        isRedesignEnabled: [
            (selectors) => [selectors.featureFlags, (_, props) => props.configScope],
            (featureFlags: FeatureFlagsSet, configScope: ConfigScopeEnumApi | null): boolean =>
                !!featureFlags[FEATURE_FLAGS.SSO_SETTINGS_REDESIGN] &&
                (configScope !== ConfigScopeEnumApi.Xaa || !!featureFlags[FEATURE_FLAGS.XAA_AUTHENTICATION]),
        ],
        isConfigScopeValid: [
            (selectors) => [selectors.identityProviderConfig, (_, props) => props.configScope],
            (config: IdentityProviderConfigApi | null, configScope: ConfigScopeEnumApi | null): boolean =>
                !!configScope && (!config?.config_scope || config.config_scope === configScope),
        ],
        hasSamlDomainScopeConflict: [
            (selectors) => [
                selectors.identityProviderConfig,
                selectors.identityProviderConfigForm,
                selectors.identityProviderConfigs,
                selectors.organizationDomains,
                (_, props) => props.configScope,
            ],
            (
                identityProviderConfig: IdentityProviderConfigApi | null,
                form: IdentityProviderConfigForm,
                configs: IdentityProviderConfigApi[] | null,
                domains: OrganizationDomainApi[] | null,
                configScope: ConfigScopeEnumApi | null
            ): boolean =>
                configScope === ConfigScopeEnumApi.Saml &&
                hasSamlDomainScopeConflict(
                    configs,
                    identityProviderConfig?.id ?? null,
                    form.domain_scope,
                    form.organization_domain_ids,
                    domains?.filter((domain) => domain.is_verified).map((domain) => domain.id) ?? []
                ),
        ],
        breadcrumbs: [
            (_, props) => [props.configScope],
            (configScope: ConfigScopeEnumApi | null): Breadcrumb[] => [
                {
                    key: Scene.Settings,
                    name: 'Settings - Authentication domains & SSO',
                    path: urls.settings('organization-authentication'),
                    iconType: 'settings',
                },
                {
                    key: Scene.IdentityProviderConfig,
                    name: configScope ? `Configure ${IDENTITY_PROVIDER_FEATURES[configScope].name}` : 'Configure SSO',
                },
            ],
        ],
    }),
    listeners(({ actions, props, values }) => ({
        setFeatureFlags: () => {
            if (!values.isRedesignEnabled) {
                router.actions.replace(urls.settings('organization-authentication'))
            }
        },
        loadIdentityProviderConfigSuccess: ({ identityProviderConfig }) => {
            actions.resetIdentityProviderConfigForm(formValuesFromConfig(identityProviderConfig))
        },
        submitIdentityProviderConfigFormSuccess: () => {
            const config = values.identityProviderConfig
            if (!config || !props.configScope) {
                return
            }

            actions.resetIdentityProviderConfigForm(values.identityProviderConfigForm)
            if (props.configId === NEW_CONFIG_ID) {
                router.actions.replace(urls.identityProviderConfig(props.configScope, config.id))
            }
            lemonToast.success(`${IDENTITY_PROVIDER_FEATURES[props.configScope].name} configuration saved.`)
        },
        submitIdentityProviderConfigFormFailure: () => {
            lemonToast.error('Could not save the identity provider configuration. Check the form and try again.')
        },
        regenerateScimTokenSuccess: ({ regeneratedScimToken }) => {
            actions.setRevealedScimToken(regeneratedScimToken)
            lemonToast.success('SCIM token regenerated.')
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.receivedFeatureFlags && !values.isRedesignEnabled) {
            router.actions.replace(urls.settings('organization-authentication'))
            return
        }
        actions.loadIdentityProviderConfig()
        actions.loadOrganizationDomains()
    }),
    propsChanged(({ actions, props, values }, oldProps) => {
        if (
            oldProps.configId !== props.configId &&
            !(oldProps.configId === NEW_CONFIG_ID && values.identityProviderConfig?.id === props.configId)
        ) {
            actions.loadIdentityProviderConfig()
        }
    }),
])
