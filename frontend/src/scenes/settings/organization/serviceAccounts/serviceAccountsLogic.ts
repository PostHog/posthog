export const serviceAccountsLogic: LogicWrapper<serviceAccountsLogicType> = kea<serviceAccountsLogicType>([
    props({} as ServiceAccountsLogicProps),
    key(({ organizationId }) => organizationId),
    path((key) => ['scenes', 'settings', 'organization', 'serviceAccounts', 'serviceAccountsLogic', key]),
    actions({
        setSearch: (search: string) => ({ search }),
        setCreating: (creating: boolean) => ({ creating }),
        selectAccount: (id: string | null) => ({ id }),
        accountCreated: (account: ServiceAccountApi) => ({ account }),
    }),
    forms(({ actions, props }) => ({
        newAccount: {
            defaults: { name: '' },
            errors: ({ name }) => ({ name: !name.trim() ? 'Enter a name for the service account.' : undefined }),
            submit: async ({ name }) => {
                const account = await serviceAccountsCreate(props.organizationId, { name: name.trim() })
                actions.accountCreated(account)
            },
        },
    })),
    loaders(({ props }) => ({
        accounts: [
            null as ServiceAccountApi[] | null,
            {
                loadAccounts: async (_: void, breakpoint) => {
                    const accounts: ServiceAccountApi[] = []
                    let next: string | null | undefined
                    do {
                        const response = await serviceAccountsList(props.organizationId, {
                            limit: 100,
                            offset: accounts.length,
                        })
                        breakpoint()
                        accounts.push(...response.results)
                        next = response.next
                    } while (next)
                    return accounts
                },
            },
        ],
    })),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        creating: [false, { setCreating: (_, { creating }) => creating, accountCreated: () => false }],
        selectedAccountId: [null as string | null, { selectAccount: (_, { id }) => id }],
        loadFailed: [
            false,
            { loadAccounts: () => false, loadAccountsSuccess: () => false, loadAccountsFailure: () => true },
        ],
        createFailed: [
            false,
            { setCreating: () => false, submitNewAccount: () => false, submitNewAccountFailure: () => true },
        ],
    }),
    selectors({
        filteredAccounts: [
            (s) => [s.accounts, s.search],
            (accounts: ServiceAccountApi[] | null, search: string): ServiceAccountApi[] =>
                (accounts ?? []).filter((account) => account.name.toLowerCase().includes(search.trim().toLowerCase())),
        ],
    }),
    listeners(({ actions }) => ({
        setCreating: ({ creating }) => {
            if (creating) {
                actions.resetNewAccount()
                posthog.capture('service account creation started')
            }
        },
        accountCreated: ({ account }) => {
            actions.loadAccounts()
            actions.selectAccount(account.id)
            posthog.capture('service account created')
        },
        submitNewAccountFailure: () => {
            posthog.capture('service account creation failed')
        },
        selectAccount: ({ id }) => {
            if (id) {
                posthog.capture('service account details viewed')
            }
        },
    })),
    actionToUrl({
        selectAccount: ({ id }) => [
            router.values.location.pathname,
            { ...router.values.searchParams, service_account: id || undefined },
            router.values.hashParams,
        ],
    }),
    urlToAction(({ actions, values }) => ({
        '*': (_, search) => {
            const id = typeof search.service_account === 'string' ? search.service_account : null
            if (id !== values.selectedAccountId) {
                actions.selectAccount(id)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadAccounts()
        posthog.capture('service accounts viewed')
    }),
])
