export type organizationMemberNoticeLogicType = MakeLogicType<
    organizationMemberNoticeLogicValues,
    organizationMemberNoticeLogicActions,
    Record<string, any>,
    organizationMemberNoticeLogicMeta
>

export const organizationMemberNoticeLogic = kea<organizationMemberNoticeLogicType>([
    path(['scenes', 'settings', 'organization', 'organizationMemberNoticeLogic']),
    connect(() => ({
        values: [organizationLogic, ['currentOrganization', 'currentOrganizationLoading']],
        actions: [organizationLogic, ['loadCurrentOrganizationSuccess', 'updateOrganizationSuccess']],
    })),
    actions({
        removeMemberNotice: true,
    }),
    forms(({ values }) => ({
        memberNotice: {
            defaults: formFromNotice(null),
            errors: ({ message, label, url }) => ({
                message: !message.trim() ? 'Add a message' : undefined,
                label: url.trim() && !label.trim() ? 'Add a button label, or clear the link' : undefined,
                url:
                    label.trim() && !url.trim()
                        ? 'Add a link, or clear the button label'
                        : url.trim() && !/^https?:\/\//i.test(url.trim())
                          ? 'The link must start with http:// or https://'
                          : undefined,
            }),
            submit: async () => {
                await organizationLogic.asyncActions.updateOrganization({ member_notice: values.draftMemberNotice })
            },
        },
    })),
    selectors({
        savedMemberNotice: [
            (s) => [s.currentOrganization],
            (currentOrganization: OrganizationType | null): OrganizationMemberNoticeApi | null =>
                currentOrganization?.member_notice ?? null,
        ],
        draftMemberNotice: [
            (s) => [s.memberNotice],
            (memberNotice: MemberNoticeForm): OrganizationMemberNoticeApi | null => noticeFromForm(memberNotice),
        ],
        hasUnsavedMemberNotice: [
            (s) => [s.draftMemberNotice, s.savedMemberNotice],
            (
                draftMemberNotice: OrganizationMemberNoticeApi | null,
                savedMemberNotice: OrganizationMemberNoticeApi | null
            ): boolean => {
                const draft = formFromNotice(draftMemberNotice)
                const saved = formFromNotice(savedMemberNotice)
                return draft.message !== saved.message || draft.label !== saved.label || draft.url !== saved.url
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        // The organization reloads after every save, so the draft follows the saved notice.
        loadCurrentOrganizationSuccess: () => {
            actions.resetMemberNotice(formFromNotice(values.savedMemberNotice))
        },
        updateOrganizationSuccess: () => {
            actions.resetMemberNotice(formFromNotice(values.savedMemberNotice))
        },
        removeMemberNotice: () => {
            organizationLogic.actions.updateOrganization({ member_notice: null })
        },
    })),
    afterMount(({ actions, values }) => {
        actions.resetMemberNotice(formFromNotice(values.savedMemberNotice))
    }),
])
