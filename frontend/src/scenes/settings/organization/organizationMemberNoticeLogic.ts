export interface MemberNoticeForm {
    message: string
    label: string
    url: string
}

function formFromNotice(notice: OrganizationMemberNoticeApi | null | undefined): MemberNoticeForm {
    return {
        message: notice?.message ?? '',
        label: notice?.action?.label ?? '',
        url: notice?.action?.url ?? '',
    }
}

function noticeFromForm({ message, label, url }: MemberNoticeForm): OrganizationMemberNoticeApi | null {
    if (!message.trim()) {
        return null
    }
    return {
        message: message.trim(),
        action: label.trim() && url.trim() ? { label: label.trim(), url: url.trim() } : null,
    }
}

