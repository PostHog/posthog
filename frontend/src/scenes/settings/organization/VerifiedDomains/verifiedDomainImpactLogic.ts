/**
 * Impact previews for the two destructive verified-domain actions: removing a verified domain while
 * membership is restricted to verified email domains, and turning that restriction on. Both fetch
 * the members who would lose access so the confirmation modal can list them.
 */
export const verifiedDomainImpactLogic = kea<verifiedDomainImpactLogicType>([
    path(['scenes', 'organization', 'verifiedDomainImpactLogic']),
    connect(() => ({
        values: [organizationLogic, ['currentOrganization']],
        actions: [organizationLogic, ['updateOrganization', 'loadCurrentOrganization']],
    })),
    actions({
        promptRemoveDomain: (domain: OrganizationDomainType) => ({ domain }),
        closeRemoveDomainPrompt: true,
        confirmRemoveDomain: true,
        promptEnforceVerifiedDomains: true,
        closeEnforcementPrompt: true,
        loadDomainImpact: (domain: OrganizationDomainType) => ({ domain }),
        loadEnforcementImpact: true,
        confirmEnforceVerifiedDomains: true,
    }),
    loaders(({ values }) => ({
        domainImpact: [
            null as CountedPaginatedResponse<OrganizationMemberType> | null,
            {
                loadDomainImpact: async ({ domain }: { domain: OrganizationDomainType }) => {
                    return await api.organizationMembers.list({
                        email_domain: domain.domain,
                        limit: IMPACTED_MEMBERS_FETCH_LIMIT,
                    })
                },
            },
        ],
        enforcementImpact: [
            null as CountedPaginatedResponse<OrganizationMemberType> | null,
            {
                loadEnforcementImpact: async () => {
                    return await api.organizationMembers.list({
                        outside_verified_domains: true,
                        // Owners are never removed, so listing them would overstate the count.
                        levels: [OrganizationMembershipLevel.Member, OrganizationMembershipLevel.Admin].join(','),
                        limit: IMPACTED_MEMBERS_FETCH_LIMIT,
                    })
                },
            },
        ],
        enforcementRemoval: [
            null as EnforcementRemovalResult | null,
            {
                confirmEnforceVerifiedDomains: async () => {
                    return await api.create<EnforcementRemovalResult>(
                        `api/organizations/${values.currentOrganization?.id}/remove_blocked_members_and_enforce_verified_domains`
                    )
                },
            },
        ],
    })),
    reducers({
        removeDomainPrompt: [
            null as OrganizationDomainType | null,
            {
                promptRemoveDomain: (_, { domain }) => domain,
                closeRemoveDomainPrompt: () => null,
            },
        ],
        domainImpact: {
            promptRemoveDomain: () => null,
        },
        enforcementPromptOpen: [
            false,
            {
                loadEnforcementImpactSuccess: (_, { enforcementImpact }) => (enforcementImpact?.count ?? 0) > 0,
                closeEnforcementPrompt: () => false,
                confirmEnforceVerifiedDomainsSuccess: () => false,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        promptRemoveDomain: ({ domain }) => {
            // The list is only meaningful when the restriction is on and the domain counts as verified.
            if (values.currentOrganization?.enforce_verified_domains && domain.is_verified) {
                actions.loadDomainImpact(domain)
            }
        },
        confirmRemoveDomain: () => {
            const domain = values.removeDomainPrompt
            if (domain) {
                verifiedDomainsLogic.actions.deleteVerifiedDomain(domain.id)
            }
            actions.closeRemoveDomainPrompt()
        },
        promptEnforceVerifiedDomains: () => {
            actions.loadEnforcementImpact()
        },
        loadEnforcementImpactSuccess: () => {
            if ((values.enforcementImpact?.count ?? 0) === 0) {
                // Nobody is impacted, no confirmation needed.
                actions.updateOrganization({ enforce_verified_domains: true })
            }
        },
        confirmEnforceVerifiedDomainsSuccess: ({ enforcementRemoval }) => {
            const removed = enforcementRemoval?.removed_members ?? 0
            lemonToast.success(
                removed === 1
                    ? 'Logins restricted to verified email domains. 1 member was removed.'
                    : `Logins restricted to verified email domains. ${removed} members were removed.`
            )
            actions.loadCurrentOrganization()
            membersLogic.findMounted()?.actions.loadAllMembers()
        },
    })),
])
