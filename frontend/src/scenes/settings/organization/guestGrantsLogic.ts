export const guestGrantsLogic = kea<guestGrantsLogicType>([
    path((inviteIndex) => ['scenes', 'settings', 'organization', 'guestGrantsLogic', inviteIndex]),
    props({} as GuestGrantsLogicProps),
    key((props) => props.inviteIndex),
    connect(() => ({
        values: [
            inviteLogic,
            ['invitesToSend'],
            teamLogic,
            ['currentTeamId'],
            organizationLogic,
            ['currentOrganizationId'],
        ],
        actions: [inviteLogic, ['updateInviteAtIndex']],
    })),
    actions({
        setActiveResource: (resource: GuestGrantResource) => ({ resource }),
        setSearch: (search: string) => ({ search }),
        toggleObject: (resource: GuestGrantResource, option: GuestGrantOption) => ({ resource, option }),
        toggleAll: (resource: GuestGrantResource) => ({ resource }),
        loadOptions: (resource: GuestGrantResource, search: string) => ({ resource, search }),
        loadOptionsSuccess: (key: string, page: GuestGrantOptionsPage) => ({ key, page }),
        loadOptionsFailure: (key: string) => ({ key }),
        loadPreviews: (grants: { resource: GuestGrantResource; id: string }[]) => ({ grants }),
        loadPreviewsSuccess: (previews: GuestGrantPreviewApi[], keys: string[]) => ({ previews, keys }),
        loadPreviewsFailure: (keys: string[]) => ({ keys }),
    }),
    reducers({
        activeResource: ['dashboard' as GuestGrantResource, { setActiveResource: (_, { resource }) => resource }],
        search: [
            '',
            {
                setSearch: (_, { search }) => search,
                setActiveResource: () => '',
            },
        ],
        optionsByKey: [
            {} as Record<string, GuestGrantOptionsPage>,
            { loadOptionsSuccess: (state, { key, page }) => ({ ...state, [key]: page }) },
        ],
        optionsLoadingKeys: [
            {} as Record<string, boolean>,
            {
                loadOptions: (state, { resource, search }) => ({ ...state, [optionsKey(resource, search)]: true }),
                loadOptionsSuccess: (state, { key }) => omitKeys(state, [key]),
                loadOptionsFailure: (state, { key }) => omitKeys(state, [key]),
            },
        ],
        previewByKey: [
            {} as Record<string, GuestGrantPreviewApi>,
            {
                loadPreviewsSuccess: (state, { previews }) => ({
                    ...state,
                    ...Object.fromEntries(previews.map((preview) => [grantKey(preview), preview])),
                }),
            },
        ],
        previewLoadingKeys: [
            {} as Record<string, boolean>,
            {
                loadPreviews: (state, { grants }) => ({
                    ...state,
                    ...Object.fromEntries(grants.map((grant) => [grantKey(grant), true])),
                }),
                loadPreviewsSuccess: (state, { keys }) => omitKeys(state, keys),
                loadPreviewsFailure: (state, { keys }) => omitKeys(state, keys),
            },
        ],
    }),
    selectors({
        grants: [
            (s, p) => [s.invitesToSend, p.inviteIndex],
            (invitesToSend: InviteRowState[], inviteIndex: number): GuestGrant[] =>
                invitesToSend[inviteIndex]?.guest_grants ?? [],
        ],
        exactPage: [
            (s) => [s.optionsByKey, s.activeResource, s.search],
            (
                optionsByKey: Record<string, GuestGrantOptionsPage>,
                activeResource: GuestGrantResource,
                search: string
            ): GuestGrantOptionsPage | null => optionsByKey[optionsKey(activeResource, search)] ?? null,
        ],
        options: [
            (s) => [s.exactPage, s.optionsByKey, s.activeResource, s.search],
            (
                exactPage: GuestGrantOptionsPage | null,
                optionsByKey: Record<string, GuestGrantOptionsPage>,
                activeResource: GuestGrantResource,
                search: string
            ): GuestGrantOption[] => {
                if (exactPage) {
                    return exactPage.options
                }
                // Until the search answers, filter the list that is already loaded.
                const needle = search.trim().toLowerCase()
                return (optionsByKey[optionsKey(activeResource, '')]?.options ?? []).filter((option) =>
                    option.name.toLowerCase().includes(needle)
                )
            },
        ],
        optionsLoading: [
            (s) => [s.optionsByKey, s.activeResource],
            (optionsByKey: Record<string, GuestGrantOptionsPage>, activeResource: GuestGrantResource): boolean =>
                !optionsByKey[optionsKey(activeResource, '')],
        ],
        optionsSearching: [
            (s) => [s.optionsLoadingKeys, s.activeResource, s.search],
            (
                optionsLoadingKeys: Record<string, boolean>,
                activeResource: GuestGrantResource,
                search: string
            ): boolean => !!search.trim() && !!optionsLoadingKeys[optionsKey(activeResource, search)],
        ],
        hiddenOptionCount: [
            (s) => [s.exactPage],
            (exactPage: GuestGrantOptionsPage | null): number =>
                exactPage ? Math.max(exactPage.count - exactPage.options.length, 0) : 0,
        ],
        allSelected: [
            (s) => [s.grants, s.activeResource],
            (grants: GuestGrant[], activeResource: GuestGrantResource): boolean =>
                grants.some((grant) => grant.resource === activeResource && grant.id === null),
        ],
        selectedIds: [
            (s) => [s.grants, s.activeResource],
            (grants: GuestGrant[], activeResource: GuestGrantResource): Set<string> =>
                new Set(
                    grants
                        .filter((grant) => grant.resource === activeResource && grant.id !== null)
                        .map((grant) => grant.id as string)
                ),
        ],
        selectedCounts: [
            (s) => [s.grants],
            (grants: GuestGrant[]): Record<GuestGrantResource, number> => {
                const counts: Record<GuestGrantResource, number> = { dashboard: 0, insight: 0, notebook: 0 }
                grants.forEach((grant) => (counts[grant.resource] += 1))
                return counts
            },
        ],
        previewItems: [
            (s) => [s.grants, s.previewByKey, s.previewLoadingKeys],
            (
                grants: GuestGrant[],
                previewByKey: Record<string, GuestGrantPreviewApi>,
                previewLoadingKeys: Record<string, boolean>
            ): GuestGrantPreviewItem[] =>
                grants.map((grant) => {
                    const cached = previewByKey[grantKey(grant)]
                    if (cached) {
                        return { ...cached, loading: false }
                    }
                    return {
                        resource: grant.resource,
                        id: grant.id,
                        name: grant.name ?? null,
                        includes: [],
                        loading: !!previewLoadingKeys[grantKey(grant)],
                    }
                }),
        ],
    }),
    listeners(({ actions, values, props }) => ({
        loadOptions: async ({ resource, search }) => {
            const key = optionsKey(resource, search)
            try {
                actions.loadOptionsSuccess(
                    key,
                    await fetchOptions(String(values.currentTeamId), resource, search.trim())
                )
            } catch {
                actions.loadOptionsFailure(key)
            }
        },
        setActiveResource: ({ resource }) => {
            const key = optionsKey(resource, '')
            if (!values.optionsByKey[key] && !values.optionsLoadingKeys[key]) {
                actions.loadOptions(resource, '')
            }
        },
        setSearch: async ({ search }, breakpoint) => {
            await breakpoint(300)
            const key = optionsKey(values.activeResource, search)
            // Notebooks are filtered from the loaded list only.
            if (
                search.trim() &&
                values.activeResource !== 'notebook' &&
                !values.optionsByKey[key] &&
                !values.optionsLoadingKeys[key]
            ) {
                actions.loadOptions(values.activeResource, search)
            }
        },
        toggleObject: ({ resource, option }) => {
            const selected = values.grants.some((grant) => grant.resource === resource && grant.id === option.id)
            actions.updateInviteAtIndex(
                {
                    guest_grants: selected
                        ? values.grants.filter((grant) => !(grant.resource === resource && grant.id === option.id))
                        : [...values.grants, { resource, id: option.id, name: option.name }],
                },
                props.inviteIndex
            )
            // An insight includes nothing else, so only dashboards and notebooks need a preview.
            if (!selected && resource !== 'insight' && !values.previewByKey[grantKey({ resource, id: option.id })]) {
                actions.loadPreviews([{ resource, id: option.id }])
            }
        },
        toggleAll: ({ resource }) => {
            const others = values.grants.filter((grant) => grant.resource !== resource)
            const allSelected = values.grants.some((grant) => grant.resource === resource && grant.id === null)
            // Every object of the type covers the single ones, so they are dropped rather than kept beside it.
            actions.updateInviteAtIndex(
                { guest_grants: allSelected ? others : [...others, { resource, id: null }] },
                props.inviteIndex
            )
        },
        loadPreviews: async ({ grants }) => {
            const keys = grants.map(grantKey)
            if (!values.currentOrganizationId || !values.currentTeamId) {
                actions.loadPreviewsFailure(keys)
                return
            }
            try {
                const response = await invitesGuestPreviewCreate(values.currentOrganizationId, {
                    project_id: values.currentTeamId,
                    grants,
                })
                actions.loadPreviewsSuccess(response.results, keys)
            } catch {
                actions.loadPreviewsFailure(keys)
            }
        },
    })),
    afterMount(({ actions, values }) => {
        RESOURCES.forEach((resource) => actions.loadOptions(resource, ''))
        const missing = values.grants.filter(
            (grant): grant is { resource: GuestGrantResource; id: string } =>
                grant.id !== null && grant.resource !== 'insight' && !values.previewByKey[grantKey(grant)]
        )
        if (missing.length) {
            actions.loadPreviews(missing.map(({ resource, id }) => ({ resource, id })))
        }
    }),
])
