export type GuestGrantResource = GuestGrant['resource']

export interface GuestGrantOption {
    id: string
    name: string
}

export interface GuestGrantOptionsPage {
    options: GuestGrantOption[]
    count: number
}

/** A pick in the preview. `loading` is true while the items it includes are still loading. */
export interface GuestGrantPreviewItem extends GuestGrantPreviewApi {
    loading: boolean
}

