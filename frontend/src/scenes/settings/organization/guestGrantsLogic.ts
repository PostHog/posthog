const RESOURCES: GuestGrantResource[] = ['dashboard', 'insight', 'notebook']
const OPTIONS_LIMIT = 50
// The notebooks list API has no name search, so the picker loads this many and filters them here.
const NOTEBOOKS_LIMIT = 200

const optionsKey = (resource: GuestGrantResource, search: string): string =>
    `${resource}:${search.trim().toLowerCase()}`
const grantKey = (grant: { resource: string; id: string | null }): string => `${grant.resource}:${grant.id}`
const omitKeys = <T>(state: Record<string, T>, keys: string[]): Record<string, T> =>
    Object.fromEntries(Object.entries(state).filter(([key]) => !keys.includes(key)))

async function fetchOptions(
    projectId: string,
    resource: GuestGrantResource,
    search: string
): Promise<GuestGrantOptionsPage> {
    if (resource === 'dashboard') {
        const response = await dashboardsList(projectId, { search: search || undefined, limit: OPTIONS_LIMIT })
        return {
            count: response.count,
            options: response.results.map((dashboard) => ({
                id: String(dashboard.id),
                name: dashboard.name || 'Untitled dashboard',
            })),
        }
    }
    if (resource === 'insight') {
        const response = await insightsList(projectId, {
            saved: true,
            basic: true,
            search: search || undefined,
            limit: OPTIONS_LIMIT,
        })
        return {
            count: response.count,
            options: response.results.map((insight) => ({
                id: String(insight.id),
                name: insight.name || insight.derived_name || 'Untitled insight',
            })),
        }
    }
    const response = await notebooksList(projectId, { limit: NOTEBOOKS_LIMIT })
    return {
        count: response.count,
        options: response.results.map((notebook) => ({
            id: String(notebook.id),
            name: notebook.title || 'Untitled notebook',
        })),
    }
}

