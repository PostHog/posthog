export const oauthAppReviewNoteLogic = kea<oauthAppReviewNoteLogicType>([
    path((appId) => ['scenes', 'settings', 'organization', 'OAuthApplication', 'oauthAppReviewNoteLogic', appId]),
    props({} as OAuthAppReviewNoteLogicProps),
    key((props) => props.appId),

    actions({
        openNotePreview: true,
        closeNotePreview: true,
    }),

    reducers({
        isNotePreviewOpen: [
            false,
            {
                openNotePreview: () => true,
                closeNotePreview: () => false,
                submitReviewNoteSuccess: () => false,
                submitReviewNoteFailure: () => false,
            },
        ],
    }),

    forms(({ props, actions }) => ({
        reviewNote: {
            defaults: { note: '' },
            // Previewing an empty note touches the field, so its error shows before anything is sent.
            options: { showErrorsOnTouch: true },
            errors: ({ note }) => ({
                note: !note.trim() ? 'Write a note for PostHog staff' : undefined,
            }),
            submit: async ({ note }) => {
                try {
                    const app = await oauthApplicationsReviewNoteCreate(
                        ApiConfig.getCurrentOrganizationId(),
                        props.appId,
                        { note }
                    )
                    oauthApplicationLogic.findMounted({ id: props.appId })?.actions.replaceApplication(app)
                    oauthAppsLogic.findMounted()?.actions.replaceOAuthApp(app)
                } catch (error) {
                    // A 400 on the note says why the review can't take one now, such as a block that landed after
                    // the page loaded. Rethrowing keeps the form on its failure path, which shows the error.
                    if (error instanceof ApiError && error.status === 400 && error.attr === 'note' && error.detail) {
                        actions.setReviewNoteManualErrors({ note: error.detail })
                        oauthApplicationLogic.findMounted({ id: props.appId })?.actions.loadApplication()
                        oauthAppsLogic.findMounted()?.actions.loadOAuthApps()
                    } else {
                        lemonToast.error(
                            "Couldn't send the note. Try again, and if it keeps happening contact support."
                        )
                    }
                    throw error
                }
                actions.resetReviewNote()
                lemonToast.success('Sent. PostHog staff will review the application again.')
            },
        },
    })),

    listeners(({ actions, values }) => ({
        openNotePreview: () => {
            if (!values.reviewNote.note.trim()) {
                actions.closeNotePreview()
                actions.touchReviewNoteField('note')
            }
        },
    })),
])
