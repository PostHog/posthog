import { decode } from 'he'
import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { ApiConfig, ApiError } from 'lib/api'
import { supportLogic } from 'lib/components/Support/supportLogic'
import { Scene } from 'scenes/sceneTypes'
import { urls } from 'scenes/urls'

import { oauthApplicationsRetrieve } from '~/generated/core/api'
import { OrganizationOAuthApplicationDetailApi } from '~/generated/core/api.schemas'
import type { Breadcrumb } from '~/types'

import { reviewSupportMessage, verificationRequestMessage } from '../oauthAppSupportMessages'

export type OAuthAppSupportRequest = 'review' | 'verification'

export interface OAuthApplicationLogicProps {
    id: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface oauthApplicationLogicValues {
    application: OrganizationOAuthApplicationDetailApi | null
    applicationLoadFailed: boolean
    applicationLoading: boolean
    applicationNotFound: boolean
    breadcrumbs: Breadcrumb[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface oauthApplicationLogicActions {
    contactSupport: (request: OAuthAppSupportRequest) => {
        request: OAuthAppSupportRequest
    }
    loadApplication: () => any
    loadApplicationFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadApplicationSuccess: (
        application: OrganizationOAuthApplicationDetailApi,
        payload?: any
    ) => {
        application: OrganizationOAuthApplicationDetailApi
        payload?: any
    }
    replaceApplication: (application: OrganizationOAuthApplicationDetailApi) => {
        application: OrganizationOAuthApplicationDetailApi
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface oauthApplicationLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        breadcrumbs: (application: OrganizationOAuthApplicationDetailApi | null) => Breadcrumb[]
    }
}

export type oauthApplicationLogicType = MakeLogicType<
    oauthApplicationLogicValues,
    oauthApplicationLogicActions,
    OAuthApplicationLogicProps,
    oauthApplicationLogicMeta
>

export const oauthApplicationLogic = kea<oauthApplicationLogicType>([
    path((id) => ['scenes', 'settings', 'organization', 'OAuthApplication', 'oauthApplicationLogic', id]),
    props({} as OAuthApplicationLogicProps),
    key((props) => props.id),

    actions({
        replaceApplication: (application: OrganizationOAuthApplicationDetailApi) => ({ application }),
        contactSupport: (request: OAuthAppSupportRequest) => ({ request }),
    }),

    loaders(({ props }) => ({
        application: [
            null as OrganizationOAuthApplicationDetailApi | null,
            {
                loadApplication: async () =>
                    await oauthApplicationsRetrieve(ApiConfig.getCurrentOrganizationId(), props.id),
            },
        ],
    })),

    reducers({
        application: {
            replaceApplication: (_, { application }) => application,
        },
        applicationLoadFailed: [
            false,
            {
                loadApplication: () => false,
                loadApplicationSuccess: () => false,
                loadApplicationFailure: () => true,
            },
        ],
        applicationNotFound: [
            false,
            {
                loadApplication: () => false,
                loadApplicationFailure: (_, { errorObject }) =>
                    errorObject instanceof ApiError && errorObject.status === 404,
            },
        ],
    }),

    selectors({
        breadcrumbs: [
            (s) => [s.application],
            (application: OrganizationOAuthApplicationDetailApi | null): Breadcrumb[] => [
                {
                    key: Scene.Settings,
                    name: 'Settings - OAuth applications',
                    path: urls.settings('organization-oauth-apps'),
                    iconType: 'settings',
                },
                {
                    key: Scene.OAuthApplication,
                    name: application ? decode(application.name ?? '') : 'OAuth application',
                },
            ],
        ],
    }),

    listeners(({ values }) => ({
        contactSupport: ({ request }) => {
            const app = values.application
            if (!app) {
                return
            }
            // pinned: analytics event name and properties
            posthog.capture('oauth app support requested', {
                request,
                provisioning_status: app.provisioning_status,
                review_status: app.provisioning_review?.status ?? null,
                is_verified: app.is_verified ?? false,
            })
            supportLogic.actions.openSupportForm({
                kind: 'support',
                isEmailFormOpen: true,
                oauth_app_request: true,
                message: request === 'review' ? reviewSupportMessage(app) : verificationRequestMessage(app),
            })
        },
    })),

    afterMount(({ actions }) => {
        actions.loadApplication()
    }),
])
