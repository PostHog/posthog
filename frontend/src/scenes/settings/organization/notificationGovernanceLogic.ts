export const MEMBERS_PER_PAGE = 20

const CONCEPTS_BY_SETTING = new Map(NOTIFICATION_CONCEPTS.map((concept) => [concept.setting as string, concept]))

/** One list of people: a setting, and the project it is scoped to (empty when it is not). */
export function listKey(setting: string, scopeId: string): string {
    return `${setting}::${scopeId}`
}

export function ruleKey(setting: string, scopeId: string, userId: number): string {
    return `${setting}::${scopeId}::${userId}`
}

export type PendingRules = Record<string, NotificationRuleValue>
export type MemberListView = {
    query: string
    searching: boolean
    total: number
    matching: number
    shown: OrganizationNotificationMemberApi[]
    editableIds: number[]
    page: number
    pages: number
    start: number
}
export type ListView = { query: string; page: number }

