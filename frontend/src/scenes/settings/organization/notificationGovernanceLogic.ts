/** Identifies one control: a member (or everyone), a setting, and what it is scoped to. */
export const ALL_MEMBERS = 'all'

export type ControlTarget = number | typeof ALL_MEMBERS

export function controlKey(target: ControlTarget, setting: string, scopeId: string): string {
    return `${target}::${setting}::${scopeId}`
}

/**
 * Pending values are held in the form the API stores, not the form the checkbox shows, so that
 * saving needs no conversion. Some settings are stored as "disabled", so the two are opposites.
 * null means "remove the lock and give the member their own choice back".
 */
export type PendingChanges = Record<string, boolean | null>

