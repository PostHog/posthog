export const notificationGovernanceLogic = kea<notificationGovernanceLogicType>([
    path(['scenes', 'settings', 'organization', 'notificationGovernanceLogic']),
    connect(() => ({
        values: [organizationLogic, ['currentOrganization']],
    })),
    actions({
        setControl: (target: ControlTarget, setting: string, scopeId: string, checked: boolean | null) => ({
            target,
            setting,
            scopeId,
            checked,
        }),
        discardChanges: true,
        saveChanges: true,
        saveChangesSuccess: true,
        saveChangesFailure: true,
    }),
    loaders(({ values }) => ({
        // Null until the first response, so the section can tell loading apart from an
        // organization that has nothing to show.
        members: [
            null as OrganizationNotificationMemberApi[] | null,
            {
                loadMembers: async () => {
                    if (!values.currentOrganization) {
                        return []
                    }
                    return await notificationLocksList(values.currentOrganization.id)
                },
            },
        ],
        pipelines: [
            null as PipelineItem[] | null,
            {
                loadPipelines: async () => {
                    const teams = values.currentOrganization?.teams ?? []
                    const perTeam = await Promise.all(teams.map((team) => loadTeamPipelines(team)))
                    return perTeam.flat()
                },
            },
        ],
    })),
    reducers({
        pendingChanges: [
            {} as PendingChanges,
            {
                setControl: (state, { target, setting, scopeId, checked }) => ({
                    ...state,
                    [controlKey(target, setting, scopeId)]: checked,
                }),
                discardChanges: () => ({}),
                saveChangesSuccess: () => ({}),
            },
        ],
        savingChanges: [
            false,
            {
                saveChanges: () => true,
                saveChangesSuccess: () => false,
                saveChangesFailure: () => false,
            },
        ],
    }),
    selectors({
        editableMembers: [
            (s) => [s.members],
            (members: OrganizationNotificationMemberApi[] | null): OrganizationNotificationMemberApi[] =>
                (members ?? []).filter((member) => member.editable),
        ],
        changesToSave: [
            (s) => [s.pendingChanges],
            (pendingChanges: PendingChanges): OrganizationNotificationLockChangeApi[] =>
                Object.entries(pendingChanges).map(([key, checked]) => {
                    const [target, setting, scopeId] = key.split('::')
                    return {
                        user_id: target === ALL_MEMBERS ? null : Number(target),
                        // Safe: the key was built from a descriptor, whose setting is the enum.
                        setting: setting as SettingEnumApi,
                        scope_id: scopeId,
                        locked_value: checked,
                    }
                }),
        ],
        pendingChangeCount: [
            (s) => [s.changesToSave],
            (changesToSave: OrganizationNotificationLockChangeApi[]): number => changesToSave.length,
        ],
        affectedMemberCount: [
            (s) => [s.changesToSave, s.editableMembers],
            (
                changesToSave: OrganizationNotificationLockChangeApi[],
                editableMembers: OrganizationNotificationMemberApi[]
            ): number => {
                if (changesToSave.some((change) => change.user_id === null)) {
                    return editableMembers.length
                }
                return new Set(changesToSave.map((change) => change.user_id)).size
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        saveChanges: async () => {
            if (!values.changesToSave.length || !values.currentOrganization) {
                actions.saveChangesSuccess()
                return
            }
            try {
                await notificationLocksBulkUpdateCreate(values.currentOrganization.id, {
                    changes: values.changesToSave,
                })
            } catch (error) {
                actions.saveChangesFailure()
                lemonToast.error("Couldn't save the changes. Try again, and if it keeps happening contact support.")
                throw error
            }
            actions.saveChangesSuccess()
            actions.loadMembers()
            lemonToast.success('Notification settings saved')
        },
    })),
    afterMount(({ actions }) => {
        actions.loadMembers()
        actions.loadPipelines()
    }),
])

/**
 * What a control should show for one member: whether they receive the notification, and whether
 * an organization lock is deciding that.
 */
export function resolveControl(
    member: OrganizationNotificationMemberApi,
    descriptor: NotificationSettingDescriptor,
    scopeId: string,
    pendingChanges: PendingChanges
): { checked: boolean; locked: boolean; lockedForEveryone: boolean } {
    // A pending value of null means "unlock", so presence has to be checked rather than
    // truthiness, and a change aimed at one member wins over one aimed at everyone.
    const memberKey = controlKey(member.user_id, descriptor.setting, scopeId)
    const everyoneKey = controlKey(ALL_MEMBERS, descriptor.setting, scopeId)
    const pendingKey = memberKey in pendingChanges ? memberKey : everyoneKey in pendingChanges ? everyoneKey : null
    if (pendingKey !== null) {
        const pending = pendingChanges[pendingKey]
        return {
            checked:
                pending === null
                    ? storedValueFor(member.notification_settings, descriptor, scopeId)
                    : storedToCheckedValue(descriptor, pending),
            locked: pending !== null,
            lockedForEveryone: false,
        }
    }

    const lock = member.locks.find((entry) => entry.setting === descriptor.setting && entry.scope_id === scopeId)
    if (lock) {
        return {
            checked: storedToCheckedValue(descriptor, lock.locked_value),
            locked: true,
            lockedForEveryone: lock.applies_to_all_members,
        }
    }

    return {
        checked: storedValueFor(member.notification_settings, descriptor, scopeId),
        locked: false,
        lockedForEveryone: false,
    }
}

/** The stored form of a ticked control, which is what the API and send-time code read. */
export function storedValueForControl(descriptor: NotificationSettingDescriptor, checked: boolean): boolean {
    return checkedToStoredValue(descriptor, checked)
}
