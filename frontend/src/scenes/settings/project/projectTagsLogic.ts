export const projectTagsLogic = kea<projectTagsLogicType>([
    path(['scenes', 'settings', 'project', 'projectTagsLogic']),
    connect({
        values: [
            projectLogic,
            ['currentProject', 'currentProjectLoading'],
            organizationLogic,
            ['currentOrganization'],
            teamLogic,
            ['currentTeam'],
        ],
        actions: [projectLogic, ['updateCurrentProject']],
    }),
    actions({
        updateTags: (tags: string[]) => ({ tags }),
    }),
    reducers(() => ({
        projectGroupSaveError: [
            null as string | null,
            {
                submitProjectGroupRequest: () => null,
                [projectLogic.actionTypes.updateCurrentProjectFailure]: (_, { error }) => error,
            },
        ],
    })),
    forms(({ values }) => ({
        projectGroup: {
            defaults: { name: '' },
            errors: ({ name }) => ({
                name:
                    name.trim() && !projectGroupTagFromName(name)
                        ? 'Use at least one letter (a-z) or number in the group name.'
                        : undefined,
            }),
            submit: async ({ name }): Promise<void> => {
                if (!values.canEditProjectGroup || values.currentProjectLoading || !values.projectGroupTagChanged) {
                    return
                }
                const tag = projectGroupTagFromName(name)
                await projectLogic.asyncActions.updateCurrentProject({
                    tags: tag ? [...values.regularTags, tag] : values.regularTags,
                })
                if (values.projectGroupSaveError) {
                    throw new Error(values.projectGroupSaveError)
                }
            },
        },
    })),
    selectors({
        projectGroupName: [
            (s) => [s.currentProject],
            (currentProject: ProjectType | null): string | null => projectGroupFromTags(currentProject?.tags),
        ],
        projectGroupTag: [
            (s) => [s.projectGroupName],
            (name: string | null): string | null => (name ? `${PROJECT_GROUP_TAG_PREFIX}${name}` : null),
        ],
        regularTags: [
            (s) => [s.currentProject],
            (currentProject: ProjectType | null): string[] =>
                (currentProject?.tags ?? []).filter((tag) => !isProjectGroupTag(tag)),
        ],
        canEditProjectGroup: [
            (s) => [s.currentOrganization, s.currentTeam],
            (organization: OrganizationType | null, team: TeamPublicType | TeamType | null): boolean =>
                (organization?.membership_level ?? 0) >= OrganizationMembershipLevel.Admin &&
                isAuthenticatedTeam(team) &&
                (team.effective_membership_level ?? 0) >= TeamMembershipLevel.Member,
        ],
        projectGroupTagChanged: [
            (s) => [s.projectGroup, s.projectGroupTag],
            ({ name }: { name: string }, tag: string | null): boolean => projectGroupTagFromName(name) !== tag,
        ],
        projectGroupOptions: [
            (s) => [s.currentOrganization],
            (organization: OrganizationType | null): { key: string; value: string; label: string }[] =>
                uniqueProjectGroupNames(organization?.teams.map((team) => team.project_group) ?? []).map((value) => ({
                    key: value,
                    value,
                    label: identifierToHuman(value, 'sentence'),
                })),
        ],
    }),
    listeners(({ actions, values }) => ({
        updateTags: ({ tags }): void => {
            if (!values.currentProjectLoading) {
                actions.updateCurrentProject({
                    tags: values.projectGroupTag ? [...tags, values.projectGroupTag] : tags,
                })
            }
        },
        [projectLogic.actionTypes.loadCurrentProjectSuccess]: (): void => {
            actions.resetProjectGroup({ name: values.projectGroupName ?? '' })
        },
        submitProjectGroupSuccess: (): void => {
            actions.resetProjectGroup({ name: values.projectGroupName ?? '' })
        },
    })),
    afterMount(({ actions, values }) => {
        actions.resetProjectGroup({ name: values.projectGroupName ?? '' })
    }),
])
