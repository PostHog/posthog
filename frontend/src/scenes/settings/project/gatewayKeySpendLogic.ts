import { MakeLogicType, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { ProjectSecretAPIKeyApi } from '~/generated/core/api.schemas'

import { GatewayCredentialSpend, fetchGatewaySpendByCredential } from './gatewayKeySpendQuery'
import { projectSecretAPIKeysLogic } from './projectSecretAPIKeysLogic'

export const GATEWAY_SCOPE = 'llm_gateway:read'

export interface GatewayKeySpendRow {
    id: string
    label: string
    maskValue: string | null
    requests: number
    costUsd: number
}

export interface GatewayKeySpendSummary {
    rows: GatewayKeySpendRow[]
    /** Spend whose credential matches no current key: the key was rolled or deleted since. */
    unmatchedCostUsd: number
    /** Spend from generations made before the gateway attributed keys. */
    untaggedCostUsd: number
}

// A key is listed when it can call the gateway or has spend to show, so a key that lost the scope
// still accounts for what it spent while it had it.
export function buildGatewayKeySpendSummary(
    keys: ProjectSecretAPIKeyApi[],
    spend: GatewayCredentialSpend[] | null
): GatewayKeySpendSummary {
    const byCredential = new Map<string, GatewayCredentialSpend>()
    for (const entry of spend ?? []) {
        if (entry.credential) {
            byCredential.set(entry.credential, entry)
        }
    }
    const matched = new Set<string>()
    const rows: GatewayKeySpendRow[] = []
    for (const key of keys) {
        const hit = key.ai_credential ? byCredential.get(key.ai_credential) : undefined
        if (!hit && !key.scopes.includes(GATEWAY_SCOPE)) {
            continue
        }
        if (key.ai_credential) {
            matched.add(key.ai_credential)
        }
        rows.push({
            id: key.id,
            label: key.label,
            maskValue: key.mask_value,
            requests: hit?.requests ?? 0,
            costUsd: hit?.costUsd ?? 0,
        })
    }
    rows.sort((a, b) => b.costUsd - a.costUsd)

    let unmatchedCostUsd = 0
    let untaggedCostUsd = 0
    for (const entry of spend ?? []) {
        if (!entry.credential) {
            untaggedCostUsd += entry.costUsd
        } else if (!matched.has(entry.credential)) {
            unmatchedCostUsd += entry.costUsd
        }
    }
    return { rows, unmatchedCostUsd, untaggedCostUsd }
}

