export type gatewayKeySpendLogicType = MakeLogicType<
    gatewayKeySpendLogicValues,
    gatewayKeySpendLogicActions,
    Record<string, any>,
    gatewayKeySpendLogicMeta
>

export const gatewayKeySpendLogic = kea<gatewayKeySpendLogicType>([
    path(['scenes', 'settings', 'project', 'gatewayKeySpendLogic']),
    connect(() => ({
        values: [projectSecretAPIKeysLogic, ['keys']],
        actions: [projectSecretAPIKeysLogic, ['loadKeysSuccess']],
    })),
    // null until the first query answers, so the table shows skeletons rather than zeros.
    loaders(() => ({
        spend: [
            null as GatewayCredentialSpend[] | null,
            {
                loadSpend: async () => await fetchGatewaySpendByCredential(),
            },
        ],
    })),
    reducers({
        spendFailed: [false, { loadSpend: () => false, loadSpendFailure: () => true }],
    }),
    selectors({
        hasGatewayKeys: [
            (s) => [s.keys],
            (keys: ProjectSecretAPIKeyApi[]): boolean => keys.some((key) => key.scopes.includes(GATEWAY_SCOPE)),
        ],
        summary: [
            (s) => [s.keys, s.spend],
            (keys: ProjectSecretAPIKeyApi[], spend: GatewayCredentialSpend[] | null): GatewayKeySpendSummary =>
                buildGatewayKeySpendSummary(keys, spend),
        ],
    }),
    // The query runs only for a project with a gateway key, so every other settings visit skips it.
    listeners(({ actions, values }) => ({
        loadKeysSuccess: () => {
            if (values.hasGatewayKeys) {
                actions.loadSpend()
            }
        },
    })),
    afterMount(({ actions, values }) => {
        if (values.hasGatewayKeys) {
            actions.loadSpend()
        }
    }),
])
