export type WorkloadTrustPolicyFormValues = Pick<
    WorkloadTrustPolicyApi,
    'name' | 'issuer' | 'subject_name' | 'subject' | 'scopes'
> & {
    /** A supported provider's key, or `custom` for another OIDC issuer. */
    provider_key: WorkloadProviderKeyEnumApi | ''
    /** Claim name to required value. A condition that isn't set has no key. */
    conditions: Record<string, string>
    /** Only for another OIDC issuer, where the admin names the claims. */
    subject_claim: string
    subject_name_claim: string
}

export const CUSTOM_PROVIDER_KEY = WorkloadProviderKeyEnumApi.Custom

export interface WorkloadTrustPolicyScopeRow {
    key: string
    label: string
    disabledActions: APIScopeAction[]
}

const POLICIES_PAGE_SIZE = 100

const EMPTY_FORM: WorkloadTrustPolicyFormValues = {
    name: '',
    provider_key: '',
    issuer: '',
    subject_name: '',
    subject: '',
    subject_claim: '',
    subject_name_claim: '',
    conditions: {},
    scopes: [],
}

function formFromPolicy(policy: WorkloadTrustPolicyApi): WorkloadTrustPolicyFormValues {
    return {
        name: policy.name,
        provider_key: (policy.provider as WorkloadProviderKeyEnumApi | null) ?? '',
        issuer: policy.issuer,
        subject_name: policy.subject_name,
        subject: policy.subject,
        subject_claim: policy.subject_claim ?? '',
        subject_name_claim: policy.subject_name_claim ?? '',
        conditions: { ...policy.conditions },
        scopes: policy.scopes,
    }
}

