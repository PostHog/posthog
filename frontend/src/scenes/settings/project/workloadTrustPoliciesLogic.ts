export const workloadTrustPoliciesLogic = kea<workloadTrustPoliciesLogicType>([
    path(['scenes', 'settings', 'project', 'workloadTrustPoliciesLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    actions({
        setEditingPolicyId: (id: WorkloadTrustPolicyApi['id'] | 'new' | null) => ({ id }),
        setScopeLevel: (key: string, level: ScopeAccessLevel) => ({ key, level }),
        setConditionRows: (rows: WorkloadConditionRow[]) => ({ rows }),
        resetConditionRows: (rows: WorkloadConditionRow[]) => ({ rows }),
        lookUpSubject: true,
        checkIssuer: true,
        setCheckedIssuer: (issuer: string) => ({ issuer }),
        showSetup: true,
        setScopeSearchTerm: (searchTerm: string) => ({ searchTerm }),
        deletePolicy: (policy: WorkloadTrustPolicyApi) => ({ policy }),
    }),

    reducers({
        editingPolicyId: [
            null as WorkloadTrustPolicyApi['id'] | 'new' | null,
            {
                setEditingPolicyId: (_, { id }) => id,
            },
        ],
        scopeSearchTerm: [
            '',
            {
                setScopeSearchTerm: (_, { searchTerm }) => searchTerm,
                setEditingPolicyId: () => '',
            },
        ],
        conditionRows: [
            [] as WorkloadConditionRow[],
            {
                setConditionRows: (_, { rows }) => rows,
                resetConditionRows: (_, { rows }) => rows,
            },
        ],
        showingSetup: [
            false,
            {
                showSetup: () => true,
                setEditingPolicyId: () => false,
            },
        ],
        checkedIssuer: [
            '',
            {
                setCheckedIssuer: (_, { issuer }) => issuer,
                setEditingPolicyId: () => '',
            },
        ],
        issuerCheckError: [
            null as string | null,
            {
                checkIssuer: () => null,
                checkIssuerFailure: (_, { error }) => error,
                setEditingPolicyId: () => null,
                setEditingPolicyValue: (state, { name }) => (name === 'issuer' ? null : state),
            },
        ],
        subjectLookupError: [
            null as string | null,
            {
                lookUpSubject: () => null,
                lookUpSubjectFailure: (_, { error }) => error,
                setEditingPolicyId: () => null,
                setEditingPolicyValue: (state, { name }) => (name === 'subject_name' ? null : state),
            },
        ],
    }),

    loaders(({ actions, values, cache }) => ({
        policies: [
            null as WorkloadTrustPolicyApi[] | null,
            {
                loadPolicies: async () => {
                    const projectId = String(values.currentTeamId)
                    // Every policy stays active until someone disables it, so the list must show all of them.
                    const policies: WorkloadTrustPolicyApi[] = []
                    let hasNextPage = true
                    while (hasNextPage) {
                        const page = await workloadTrustPoliciesList(projectId, {
                            limit: POLICIES_PAGE_SIZE,
                            offset: policies.length,
                        })
                        policies.push(...page.results)
                        hasNextPage = !!page.next && page.results.length > 0
                    }
                    return policies
                },
                setPolicyEnabled: async ({ policy, enabled }: { policy: WorkloadTrustPolicyApi; enabled: boolean }) => {
                    try {
                        const updated = await workloadTrustPoliciesPartialUpdate(
                            String(values.currentTeamId),
                            policy.id,
                            {
                                enabled,
                            }
                        )
                        posthog.capture('workload trust policy enabled changed', { enabled })
                        return (values.policies ?? []).map((row) => (row.id === updated.id ? updated : row))
                    } catch (error) {
                        lemonToast.error(readableErrorMessage(error) ?? "Couldn't update the policy. Try again.")
                        throw error
                    }
                },
            },
        ],
        providers: [
            null as WorkloadProvidersResponseApi | null,
            {
                loadProviders: async () => await workloadTrustPoliciesProvidersRetrieve(String(values.currentTeamId)),
            },
        ],
        issuerCheck: [
            null as CustomIssuerApi | null,
            {
                checkIssuer: async (): Promise<CustomIssuerApi | null> => {
                    actions.setCheckedIssuer(values.editingPolicy.issuer.trim())
                    try {
                        return await workloadTrustPoliciesCheckIssuerRetrieve(String(values.currentTeamId), {
                            issuer: values.editingPolicy.issuer.trim(),
                        })
                    } catch (error) {
                        throw new Error(readableErrorMessage(error) ?? "Couldn't check the issuer.")
                    }
                },
            },
        ],
        subjectLookup: [
            null as ResolvedWorkloadSubjectApi | null,
            {
                lookUpSubject: async (): Promise<ResolvedWorkloadSubjectApi | null> => {
                    cache.lookedUpName = values.editingPolicy.subject_name.trim()
                    try {
                        return await workloadTrustPolicyRequestsResolveSubjectRetrieve(String(values.currentTeamId), {
                            issuer: values.editingPolicy.issuer,
                            subject_name: cache.lookedUpName,
                        })
                    } catch (error) {
                        throw new Error(
                            readableErrorMessage(error) ?? `Couldn't look up the ${values.claimLabels.subjectName}.`
                        )
                    }
                },
            },
        ],
    })),

    reducers({
        policiesLoadFailed: [
            false,
            {
                loadPolicies: () => false,
                loadPoliciesFailure: () => true,
            },
        ],
        providersLoadFailed: [
            false,
            {
                loadProviders: () => false,
                loadProvidersFailure: () => true,
            },
        ],
    }),

    forms(({ values, actions }) => ({
        editingPolicy: {
            defaults: EMPTY_FORM,
            errors: ({ name, provider_key, issuer, subject_name, subject, subject_claim, conditions, scopes }) => ({
                name: !name ? 'Give the policy a name' : undefined,
                provider_key: !provider_key ? 'Choose a provider' : undefined,
                issuer: !issuer ? 'Enter the issuer URL' : undefined,
                subject_claim:
                    provider_key === CUSTOM_PROVIDER_KEY && !subject_claim ? 'Enter the subject claim' : undefined,
                subject_name: !subject_name ? `${values.claimLabels.subjectName} is required` : undefined,
                subject: !subject ? `${values.claimLabels.subject} is required` : undefined,
                conditions:
                    values.conditionConflict ??
                    ((values.editingProvider?.condition_claims.length || provider_key === CUSTOM_PROVIDER_KEY) &&
                    Object.keys(conditions).length === 0
                        ? ('Choose which runs can get a token' as any)
                        : undefined),
                scopes: !scopes.length ? ('Choose at least one scope' as any) : undefined,
            }),
            submit: async ({ provider_key: _, ...payload }, breakpoint) => {
                const projectId = String(values.currentTeamId)
                const isNew = values.editingPolicyId === 'new'
                try {
                    const saved = isNew
                        ? await workloadTrustPoliciesCreate(projectId, payload)
                        : await workloadTrustPoliciesPartialUpdate(projectId, values.editingPolicyId as string, payload)
                    breakpoint()
                    posthog.capture('workload trust policy saved', { is_new: isNew, scope_count: saved.scopes.length })
                    lemonToast.success(isNew ? 'Trusted workload added' : 'Trusted workload updated')
                    actions.loadPoliciesSuccess([
                        saved,
                        ...(values.policies ?? []).filter((policy) => policy.id !== saved.id),
                    ])
                    if (isNew && values.editingProvider?.setup_snippet) {
                        actions.showSetup()
                    } else {
                        actions.setEditingPolicyId(null)
                    }
                } catch (error) {
                    lemonToast.error(readableErrorMessage(error) ?? "Couldn't save the policy. Try again.")
                    throw error
                }
            },
        },
    })),

    selectors({
        scopeLevels: [
            (s) => [s.editingPolicy],
            (editingPolicy: WorkloadTrustPolicyFormValues): Record<string, ScopeAccessLevel> =>
                scopesArrayToObject(editingPolicy.scopes) as Record<string, ScopeAccessLevel>,
        ],
        scopeRows: [
            (s) => [s.providers, s.scopeSearchTerm],
            (
                providers: WorkloadProvidersResponseApi | null,
                scopeSearchTerm: string
            ): WorkloadTrustPolicyScopeRow[] => {
                const allowedByKey = new Map<string, Set<APIScopeAction>>()
                for (const scope of providers?.grantable_scopes ?? []) {
                    const [key, action] = scope.split(':') as [string, APIScopeAction]
                    allowedByKey.set(key, (allowedByKey.get(key) ?? new Set()).add(action))
                }
                const allActions: APIScopeAction[] = ['read', 'write']
                return Array.from(allowedByKey.entries())
                    .map(([key, allowed]) => {
                        const apiScope = API_SCOPES.find((scope) => scope.key === key)
                        return {
                            key,
                            label: apiScope?.objectName ?? capitalizeFirstLetter(key.replace(/_/g, ' ')),
                            objectPlural: apiScope?.objectPlural,
                            disabledActions: allActions.filter((action) => !allowed.has(action)),
                        }
                    })
                    .filter((row) => scopeMatchesSearch(row, scopeSearchTerm))
                    .sort((a, b) => a.label.localeCompare(b.label))
            },
        ],
        editingProvider: [
            (s) => [s.providers, s.editingPolicy],
            (
                providers: WorkloadProvidersResponseApi | null,
                editingPolicy: WorkloadTrustPolicyFormValues
            ): WorkloadProviderApi | null =>
                providers?.supported.find((provider) => provider.key === editingPolicy.provider_key) ?? null,
        ],
        isCustom: [
            (s) => [s.editingPolicy],
            (editingPolicy: WorkloadTrustPolicyFormValues): boolean =>
                editingPolicy.provider_key === CUSTOM_PROVIDER_KEY,
        ],
        conditionConflict: [
            (s) => [s.conditionRows, s.editingProvider],
            (rows: WorkloadConditionRow[], editingProvider: WorkloadProviderApi | null): string | undefined =>
                conditionsFromRows(rows, editingProvider).conflict,
        ],
        setupSnippet: [
            (s) => [s.showingSetup, s.editingProvider, s.providers],
            (
                showingSetup: boolean,
                provider: WorkloadProviderApi | null,
                providers: WorkloadProvidersResponseApi | null
            ): { snippet: string; providerName: string; docsUrl: string; jobSettings: WorkloadJobSettingsApi } | null =>
                showingSetup && provider?.setup_snippet && providers
                    ? {
                          snippet: provider.setup_snippet,
                          providerName: provider.name,
                          docsUrl: provider.docs_url,
                          jobSettings: providers.job_settings,
                      }
                    : null,
        ],
        claimLabels: [
            (s) => [s.editingProvider],
            (editingProvider: WorkloadProviderApi | null): { subject: string; subjectName: string } => ({
                subject: editingProvider?.subject_claim.label ?? 'Subject value',
                subjectName: editingProvider?.subject_name_claim.label ?? 'Name',
            }),
        ],
        providerNames: [
            (s) => [s.providers],
            (providers: WorkloadProvidersResponseApi | null): Record<string, string> =>
                Object.fromEntries((providers?.supported ?? []).map((provider) => [provider.issuer, provider.name])),
        ],
    }),

    listeners(({ actions, values, selectors, cache }) => ({
        setEditingPolicyValue: ({ name }, _, __, previousState) => {
            const field = Array.isArray(name) ? name[0] : name
            const previous = selectors.editingPolicy(previousState)
            // Condition claims and subjects belong to one provider, so switching provider starts over.
            if (field === 'provider_key' && previous.provider_key !== values.editingPolicy.provider_key) {
                const custom = values.editingPolicy.provider_key === CUSTOM_PROVIDER_KEY
                actions.setEditingPolicyValues({
                    issuer: custom ? '' : (values.editingProvider?.issuer ?? ''),
                    subject: '',
                    subject_name: '',
                    subject_claim: custom ? (values.providers?.custom.default_subject_claim ?? 'sub') : '',
                    subject_name_claim: '',
                })
                actions.setConditionRows(
                    custom ? [emptyCustomConditionRow()] : defaultConditionRows(values.editingProvider)
                )
            }
            // A new name needs its own ID, so an ID PostHog found for another name is never saved under it.
            const lookup = values.subjectLookup
            if (
                field === 'subject_name' &&
                lookup &&
                lookup.subject === values.editingPolicy.subject &&
                lookup.subject_name !== values.editingPolicy.subject_name
            ) {
                actions.setEditingPolicyValue('subject', '')
            }
        },
        setEditingPolicyId: ({ id }) => {
            if (id === null) {
                return
            }
            const policy = id === 'new' ? null : values.policies?.find((row) => row.id === id)
            const first = values.providers?.supported[0]
            const providerKey = policy?.provider ?? first?.key ?? ''
            const provider = values.providers?.supported.find((candidate) => candidate.key === providerKey) ?? null
            const rows = policy ? rowsFromConditions(policy.conditions ?? {}, provider) : defaultConditionRows(provider)
            // The form starts from these values, so opening it doesn't count as an unsaved change.
            actions.resetEditingPolicy(
                policy
                    ? formFromPolicy(policy)
                    : {
                          ...EMPTY_FORM,
                          provider_key: first?.key ?? '',
                          issuer: first?.issuer ?? '',
                          conditions: conditionsFromRows(rows, provider).conditions,
                      }
            )
            actions.resetConditionRows(rows)
            posthog.capture('workload trust policy form opened', { is_new: id === 'new' })
        },
        setConditionRows: ({ rows }) => {
            actions.setEditingPolicyValue('conditions', conditionsFromRows(rows, values.editingProvider).conditions)
        },
        lookUpSubjectSuccess: ({ subjectLookup }) => {
            // The answer may spell the name differently, so only an edit made while the lookup ran makes it stale.
            if (subjectLookup && values.editingPolicy.subject_name.trim() === cache.lookedUpName) {
                // The provider's spelling is the one the token carries, so it replaces what was typed.
                actions.setEditingPolicyValues({
                    subject: subjectLookup.subject,
                    subject_name: subjectLookup.subject_name,
                })
                posthog.capture('workload trust policy subject looked up', { found: true })
            }
        },
        lookUpSubjectFailure: () => {
            posthog.capture('workload trust policy subject looked up', { found: false })
        },
        setScopeLevel: ({ key, level }) => {
            const levels = scopesArrayToObject(values.editingPolicy.scopes)
            if (level === 'none') {
                delete levels[key]
            } else {
                levels[key] = level
            }
            actions.setEditingPolicyValue('scopes', scopesObjectToArray(levels))
        },
        deletePolicy: ({ policy }) => {
            LemonDialog.open({
                title: `Delete "${policy.name}"?`,
                description:
                    'Workloads that match this policy stop getting tokens, and tokens it already issued stop working.',
                primaryButton: {
                    children: 'Delete policy',
                    status: 'danger',
                    onClick: async () => {
                        try {
                            await workloadTrustPoliciesDestroy(String(values.currentTeamId), policy.id)
                            posthog.capture('workload trust policy deleted')
                            lemonToast.success('Trusted workload deleted')
                            actions.loadPoliciesSuccess((values.policies ?? []).filter((row) => row.id !== policy.id))
                        } catch (error) {
                            lemonToast.error(readableErrorMessage(error) ?? "Couldn't delete the policy. Try again.")
                        }
                    },
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
    })),

    afterMount(({ actions }) => {
        actions.loadPolicies()
        actions.loadProviders()
    }),
])
