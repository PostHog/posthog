export const ciTrustPoliciesLogic = kea<ciTrustPoliciesLogicType>([
    path(['scenes', 'settings', 'project', 'ciTrustPoliciesLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    actions({
        setEditingPolicyId: (id: CITrustPolicyApi['id'] | 'new' | null) => ({ id }),
        setScopeLevel: (key: string, level: ScopeAccessLevel) => ({ key, level }),
        setScopeSearchTerm: (searchTerm: string) => ({ searchTerm }),
        deletePolicy: (policy: CITrustPolicyApi) => ({ policy }),
    }),

    reducers({
        editingPolicyId: [
            null as CITrustPolicyApi['id'] | 'new' | null,
            {
                setEditingPolicyId: (_, { id }) => id,
            },
        ],
        scopeSearchTerm: [
            '',
            {
                setScopeSearchTerm: (_, { searchTerm }) => searchTerm,
                setEditingPolicyId: () => '',
            },
        ],
    }),

    loaders(({ values }) => ({
        policies: [
            null as CITrustPolicyApi[] | null,
            {
                loadPolicies: async () => {
                    const response = await ciTrustPoliciesList(String(values.currentTeamId))
                    return response.results
                },
                setPolicyEnabled: async ({ policy, enabled }: { policy: CITrustPolicyApi; enabled: boolean }) => {
                    try {
                        const updated = await ciTrustPoliciesPartialUpdate(String(values.currentTeamId), policy.id, {
                            enabled,
                        })
                        posthog.capture('ci trust policy enabled changed', { enabled })
                        return (values.policies ?? []).map((row) => (row.id === updated.id ? updated : row))
                    } catch (error) {
                        lemonToast.error(readableErrorMessage(error) ?? "Couldn't update the policy. Try again.")
                        throw error
                    }
                },
            },
        ],
        providers: [
            null as CIProvidersResponseApi | null,
            {
                loadProviders: async () => await ciTrustPoliciesProvidersRetrieve(String(values.currentTeamId)),
            },
        ],
    })),

    reducers({
        policiesLoadFailed: [
            false,
            {
                loadPolicies: () => false,
                loadPoliciesFailure: () => true,
            },
        ],
    }),

    forms(({ values, actions }) => ({
        editingPolicy: {
            defaults: EMPTY_FORM,
            errors: ({ name, issuer, repository, repository_id, ref, environment, scopes }) => ({
                name: !name ? 'Give the policy a name' : undefined,
                issuer: !issuer ? 'Choose a CI provider' : undefined,
                repository: !repository ? 'Enter the repository' : undefined,
                repository_id: !repository_id ? 'Enter the repository ID' : undefined,
                ref: !ref && !environment ? 'Set a ref, an environment, or both' : undefined,
                scopes: !scopes.length ? ('Choose at least one scope' as any) : undefined,
            }),
            submit: async (payload, breakpoint) => {
                const projectId = String(values.currentTeamId)
                const isNew = values.editingPolicyId === 'new'
                try {
                    const saved = isNew
                        ? await ciTrustPoliciesCreate(projectId, payload)
                        : await ciTrustPoliciesPartialUpdate(projectId, values.editingPolicyId as string, payload)
                    breakpoint()
                    posthog.capture('ci trust policy saved', { is_new: isNew, scope_count: saved.scopes.length })
                    lemonToast.success(isNew ? 'CI trust policy created' : 'CI trust policy updated')
                    actions.loadPoliciesSuccess([
                        saved,
                        ...(values.policies ?? []).filter((policy) => policy.id !== saved.id),
                    ])
                    actions.setEditingPolicyId(null)
                } catch (error) {
                    lemonToast.error(readableErrorMessage(error) ?? "Couldn't save the policy. Try again.")
                    throw error
                }
            },
        },
    })),

    selectors({
        scopeLevels: [
            (s) => [s.editingPolicy],
            (editingPolicy: CITrustPolicyFormValues): Record<string, ScopeAccessLevel> =>
                scopesArrayToObject(editingPolicy.scopes) as Record<string, ScopeAccessLevel>,
        ],
        scopeRows: [
            (s) => [s.providers, s.scopeSearchTerm],
            (providers: CIProvidersResponseApi | null, scopeSearchTerm: string): CITrustPolicyScopeRow[] => {
                const allowedByKey = new Map<string, Set<APIScopeAction>>()
                for (const scope of providers?.grantable_scopes ?? []) {
                    const [key, action] = scope.split(':') as [string, APIScopeAction]
                    allowedByKey.set(key, (allowedByKey.get(key) ?? new Set()).add(action))
                }
                const allActions: APIScopeAction[] = ['read', 'write']
                return Array.from(allowedByKey.entries())
                    .map(([key, allowed]) => {
                        const apiScope = API_SCOPES.find((scope) => scope.key === key)
                        return {
                            key,
                            label: apiScope?.objectName ?? capitalizeFirstLetter(key.replace(/_/g, ' ')),
                            objectPlural: apiScope?.objectPlural,
                            disabledActions: allActions.filter((action) => !allowed.has(action)),
                        }
                    })
                    .filter((row) => scopeMatchesSearch(row, scopeSearchTerm))
                    .sort((a, b) => a.label.localeCompare(b.label))
            },
        ],
        providerNames: [
            (s) => [s.providers],
            (providers: CIProvidersResponseApi | null): Record<string, string> =>
                Object.fromEntries((providers?.supported ?? []).map((provider) => [provider.issuer, provider.name])),
        ],
    }),

    listeners(({ actions, values }) => ({
        setEditingPolicyId: ({ id }) => {
            if (id === null) {
                return
            }
            const policy = id === 'new' ? null : values.policies?.find((row) => row.id === id)
            actions.resetEditingPolicy(
                policy
                    ? {
                          name: policy.name,
                          issuer: policy.issuer,
                          repository: policy.repository,
                          repository_id: policy.repository_id,
                          ref: policy.ref ?? '',
                          environment: policy.environment ?? '',
                          scopes: policy.scopes,
                      }
                    : { ...EMPTY_FORM, issuer: values.providers?.supported[0]?.issuer ?? '' }
            )
            posthog.capture('ci trust policy form opened', { is_new: id === 'new' })
        },
        setScopeLevel: ({ key, level }) => {
            const levels = scopesArrayToObject(values.editingPolicy.scopes)
            if (level === 'none') {
                delete levels[key]
            } else {
                levels[key] = level
            }
            actions.setEditingPolicyValue('scopes', scopesObjectToArray(levels))
        },
        deletePolicy: ({ policy }) => {
            LemonDialog.open({
                title: `Delete "${policy.name}"?`,
                description:
                    'CI jobs that use this policy stop getting tokens, and tokens it already issued stop working.',
                primaryButton: {
                    children: 'Delete policy',
                    status: 'danger',
                    onClick: async () => {
                        try {
                            await ciTrustPoliciesDestroy(String(values.currentTeamId), policy.id)
                            posthog.capture('ci trust policy deleted')
                            lemonToast.success('CI trust policy deleted')
                            actions.loadPoliciesSuccess((values.policies ?? []).filter((row) => row.id !== policy.id))
                        } catch (error) {
                            lemonToast.error(readableErrorMessage(error) ?? "Couldn't delete the policy. Try again.")
                        }
                    },
                },
                secondaryButton: { children: 'Cancel' },
            })
        },
    })),

    afterMount(({ actions }) => {
        actions.loadPolicies()
        actions.loadProviders()
    }),
])
