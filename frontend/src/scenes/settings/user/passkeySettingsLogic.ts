export const passkeySettingsLogic = kea<passkeySettingsLogicType>([
    path(['scenes', 'settings', 'user', 'passkeySettingsLogic']),
    connect(() => ({
        actions: [userLogic, ['loadUser'], twoFactorLogic, ['loadStatus']],
    })),
    actions({
        beginRegistration: (label: string) => ({ label }),
        setRegistrationStep: (step: RegistrationStep) => ({ step }),
        setPendingVerificationId: (id: number | null) => ({ id }),
        dismissVerificationPrompt: true,
        verifyPasskeyCancelled: true,
        setError: (error: string | null) => ({ error }),
        clearError: true,
        deletePasskey: (id: number) => ({ id }),
        renamePasskey: (id: number, label: string) => ({ id, label }),
        verifyPasskey: (id: number) => ({ id }),
        openDeleteModal: (id: number) => ({ id }),
        closeDeleteModal: true,
        openRenameModal: (id: number, currentLabel: string) => ({ id, currentLabel }),
        closeRenameModal: true,
    }),
    reducers({
        registrationStep: [
            'idle' as RegistrationStep,
            {
                setRegistrationStep: (_, { step }) => step,
                beginRegistration: () => 'registering',
                dismissVerificationPrompt: () => 'idle',
                verifyPasskey: (state) => (state === 'awaiting_verification' ? 'verifying' : state),
                verifyPasskeyFailure: (state) => (state === 'verifying' ? 'awaiting_verification' : state),
            },
        ],
        pendingVerificationId: [
            null as number | null,
            {
                setPendingVerificationId: (_, { id }) => id,
                dismissVerificationPrompt: () => null,
            },
        ],
        verificationCancelled: [
            false,
            {
                verifyPasskey: () => false,
                verifyPasskeyCancelled: () => true,
            },
        ],
        registrationLabel: [
            '' as string,
            {
                beginRegistration: (_, { label }) => label,
                setRegistrationStep: (state, { step }) => (step === 'idle' ? '' : state),
            },
        ],
        error: [
            null as string | null,
            {
                setError: (_, { error }) => error,
                clearError: () => null,
                beginRegistration: () => null,
                verifyPasskeySuccess: () => null,
            },
        ],
        deleteModalId: [
            null as number | null,
            {
                openDeleteModal: (_, { id }) => id,
                closeDeleteModal: () => null,
                deletePasskeySuccess: () => null,
            },
        ],
        renameModal: [
            null as { id: number; currentLabel: string } | null,
            {
                openRenameModal: (_, { id, currentLabel }) => ({ id, currentLabel }),
                closeRenameModal: () => null,
                renamePasskeySuccess: () => null,
            },
        ],
        verifyingPasskeyId: [
            null as number | null,
            {
                verifyPasskey: (_, { id }) => id,
                verifyPasskeySuccess: () => null,
                verifyPasskeyFailure: () => null,
            },
        ],
    }),
    loaders(({ actions, values, cache }) => ({
        passkeys: [
            [] as PasskeyCredential[],
            {
                loadPasskeys: async () => {
                    const response = await api.get<PasskeyCredential[]>('api/webauthn/credentials/')
                    return response
                },
                deletePasskey: async ({ id }) => {
                    await api.delete(`api/webauthn/credentials/${id}/`)
                    lemonToast.success('Passkey deleted')
                    return values.passkeys.filter((p: PasskeyCredential) => p.id !== id)
                },
                renamePasskey: async ({ id, label }) => {
                    const updated = await api.update<PasskeyCredential>(`api/webauthn/credentials/${id}/`, { label })
                    lemonToast.success('Passkey renamed')
                    return values.passkeys.map((p: PasskeyCredential) => (p.id === id ? updated : p))
                },
                verifyPasskey: async ({ id }) => {
                    try {
                        // Step 1: Begin verification
                        const verifyResponse = await api.create<VerificationBeginResponse>(
                            `api/webauthn/credentials/${id}/verify`
                        )

                        // Step 2: Verify with authenticator
                        const assertion = await startAuthentication({
                            optionsJSON: {
                                challenge: verifyResponse.challenge,
                                timeout: verifyResponse.timeout,
                                rpId: verifyResponse.rpId,
                                allowCredentials: verifyResponse.allowCredentials,
                                userVerification: verifyResponse.userVerification as UserVerificationRequirement,
                            },
                        })

                        // Step 3: Complete verification
                        const updated = await api.create<PasskeyCredential>(
                            `api/webauthn/credentials/${id}/verify_complete`,
                            assertion
                        )

                        posthog.capture('passkey verification succeeded')
                        lemonToast.success('Passkey verified successfully!')
                        return values.passkeys.map((p: PasskeyCredential) => (p.id === id ? updated : p))
                    } catch (e: unknown) {
                        const cancelled = isWebAuthnCancellation(e)
                        posthog.capture('passkey verification failed', {
                            error_name: getWebAuthnErrorName(e),
                            cancelled,
                        })
                        if (cancelled) {
                            // The user dismissed the prompt, or the authenticator timed out. Throwing
                            // would show an error and report the DOMException to exception tracking.
                            actions.verifyPasskeyCancelled()
                            return values.passkeys
                        }
                        actions.setError(
                            getPasskeyErrorMessage(e, "Couldn't verify your passkey. Try again, or use another device.")
                        )
                        throw e
                    }
                },
            },
        ],
        registrationOptions: [
            null as RegistrationBeginResponse | null,
            {
                prepareRegistration: async () => {
                    // Each begin request replaces the session's registration challenge, so a click
                    // that lands while this one is in flight joins it instead of starting a second.
                    const request = api.create<RegistrationBeginResponse>('api/webauthn/register/begin')
                    cache.registrationOptionsRequest = request
                    try {
                        return await request
                    } catch {
                        // These options are a prefetch for a click that has not happened yet.
                        // `beginRegistration` asks for them again when they are missing, so a failure
                        // here must stay out of the user's way.
                        return null
                    } finally {
                        if (cache.registrationOptionsRequest === request) {
                            cache.registrationOptionsRequest = null
                        }
                    }
                },
            },
        ],
        registerPasskey: [
            null as null,
            {
                beginRegistration: async ({ label }) => {
                    posthog.capture('passkey registration started')
                    try {
                        // The browser shows the passkey prompt only while the click that started
                        // the flow still counts as user activation, and an API round trip can spend
                        // that activation before the prompt opens. So start the ceremony with the
                        // options fetched ahead of the click. When the prefetch has not answered,
                        // wait for the request it already started, and ask for options here only
                        // when no prefetch is in flight.
                        const preparedOptions = values.registrationOptions
                        const pendingOptions: Promise<RegistrationBeginResponse> | null =
                            cache.registrationOptionsRequest ?? null
                        const attestation = await (preparedOptions
                            ? startRegistration({ optionsJSON: toCreationOptions(preparedOptions) })
                            : (
                                  pendingOptions ?? api.create<RegistrationBeginResponse>('api/webauthn/register/begin')
                              ).then((options) => startRegistration({ optionsJSON: toCreationOptions(options) })))

                        const { credential_id: credentialId } = await api.create<RegistrationCompleteResponse>(
                            'api/webauthn/register/complete',
                            {
                                ...attestation,
                                label,
                            }
                        )

                        posthog.capture('passkey registration succeeded')
                        lemonToast.success('Passkey added')

                        // The passkey still has to be verified before it can sign the user in, and
                        // that second ceremony needs a user activation of its own. So hand it back
                        // to the user as a button instead of asking the browser for it here.
                        actions.setPendingVerificationId(Number(credentialId))
                        actions.setRegistrationStep('awaiting_verification')
                        actions.loadPasskeys()

                        // The server keeps one registration challenge per session and drops it on
                        // completion, so replace the prefetched options.
                        actions.prepareRegistration()

                        return null
                    } catch (e: unknown) {
                        const cancelled = isWebAuthnCancellation(e)
                        posthog.capture('passkey registration failed', {
                            error_name: getWebAuthnErrorName(e),
                            cancelled,
                        })
                        actions.setRegistrationStep('idle')
                        // Load passkeys in case the passkey was created but the request after it failed
                        actions.loadPasskeys()
                        if (cancelled) {
                            // The user dismissed the prompt, or the authenticator timed out. Throwing
                            // would show an error and report the DOMException to exception tracking.
                            return null
                        }
                        actions.setError(
                            getPasskeyErrorMessage(e, "Couldn't add your passkey. Try again, or use another device.")
                        )
                        throw e
                    }
                },
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        deletePasskeySuccess: () => {
            actions.loadUser()
            actions.loadStatus()
        },
        verifyPasskeySuccess: () => {
            if (values.verificationCancelled) {
                if (values.registrationStep === 'verifying') {
                    actions.setRegistrationStep('awaiting_verification')
                }
                return
            }
            if (values.registrationStep === 'verifying') {
                actions.setRegistrationStep('complete')
            }
            actions.setPendingVerificationId(null)
            actions.loadUser()
            actions.loadStatus()
        },
    })),
])
