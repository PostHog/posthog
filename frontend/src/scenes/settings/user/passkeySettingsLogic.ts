export interface PasskeyCredential {
    id: number
    label: string
    created_at: string
    transports: string[]
    verified: boolean
    authenticator_type: 'platform' | 'hardware' | 'hybrid' | 'unknown'
}

export interface RegistrationBeginResponse {
    rp: { id: string; name: string }
    user: { id: string; name: string; displayName: string }
    challenge: string
    pubKeyCredParams: Array<{ type: 'public-key'; alg: number }>
    timeout: number
    excludeCredentials: PublicKeyCredentialDescriptorJSON[]
    authenticatorSelection: { residentKey: string; userVerification: string }
    attestation: string
    already_registered?: boolean
}

export interface RegistrationCompleteResponse {
    success: boolean
    message: string
    credential_id: string
}

export interface VerificationBeginResponse {
    challenge: string
    timeout: number
    rpId: string
    allowCredentials: PublicKeyCredentialDescriptorJSON[]
    userVerification: string
}

export type RegistrationStep = 'idle' | 'registering' | 'awaiting_verification' | 'verifying' | 'complete'

function toCreationOptions(options: RegistrationBeginResponse): PublicKeyCredentialCreationOptionsJSON {
    return {
        rp: options.rp,
        user: options.user,
        challenge: options.challenge,
        pubKeyCredParams: options.pubKeyCredParams as PublicKeyCredentialParameters[],
        timeout: options.timeout,
        excludeCredentials: options.excludeCredentials,
        authenticatorSelection: options.authenticatorSelection as AuthenticatorSelectionCriteria,
        attestation: options.attestation as AttestationConveyancePreference,
    }
}

