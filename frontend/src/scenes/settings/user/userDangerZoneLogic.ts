import { MakeLogicType, kea } from 'kea'
import { router } from 'kea-router'

import api from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { isNotNil } from 'lib/utils/guards'
import { organizationLogic } from 'scenes/organizationLogic'
import { urls } from 'scenes/urls'
import { userLogic } from 'scenes/userLogic'

import type { OrganizationBasicType, UserType } from '~/types'

export const DELETE_CONFIRMATION_TEXT = 'permanently delete data'

/** Organization deletion runs in the background, so the list is refreshed until it clears. */
const PENDING_DELETION_POLL_MS = 5000

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userDangerZoneLogicValues {
    _leaveOrganization: null
    _leaveOrganizationLoading: boolean
    blockingOrganizations: OrganizationBasicType[]
    deleteAccountDisabledReason: string | null
    deleteUserModalOpen: boolean
    hasPendingOrganizationDeletion: boolean
    isUserDeletionConfirmed: boolean
    organizationToDelete: OrganizationBasicType | null
    user: UserType | null // userLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface userDangerZoneLogicActions {
    deleteOrganizationSuccess: (args_0: { redirectPath?: string }) => {
        redirectPath: string | undefined
    } // organizationLogic
    loadUser: (resetOnFailure?: boolean) => {
        resetOnFailure: boolean | undefined
    } // userLogic
    leaveOrganization: (organizationId: string) => string
    leaveOrganizationFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    leaveOrganizationSuccess: (
        _leaveOrganization: null,
        payload?: string
    ) => {
        _leaveOrganization: null
        payload?: string
    }
    pollPendingOrganizationDeletions: () => {
        value: true
    }
    setDeleteUserModalOpen: (open: boolean) => {
        open: boolean
    }
    setIsUserDeletionConfirmed: (confirmed: boolean) => {
        confirmed: boolean
    }
    setOrganizationToDelete: (organization: OrganizationBasicType | null) => {
        organization: OrganizationBasicType | null
    }
}

export type userDangerZoneLogicType = MakeLogicType<userDangerZoneLogicValues, userDangerZoneLogicActions>

export const userDangerZoneLogic = kea<userDangerZoneLogicType>({
    path: ['scenes', 'settings', 'user', 'userDangerZoneLogic'],
    actions: {
        setDeleteUserModalOpen: (open: boolean) => ({ open }),
        setOrganizationToDelete: (organization: OrganizationBasicType | null) => ({ organization }),
        setIsUserDeletionConfirmed: (confirmed: boolean) => ({ confirmed }),
        pollPendingOrganizationDeletions: true,
    },
    connect: {
        actions: [organizationLogic, ['deleteOrganizationSuccess'], userLogic, ['loadUser']],
        values: [userLogic, ['user']],
    },
    loaders: {
        _leaveOrganization: [
            null,
            {
                leaveOrganization: async (organizationId: string) => {
                    // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. membersDestroy() from 'products/platform_features/frontend/generated/api' serves this route, but its generated types do not describe this call yet, so fix the endpoint's OpenAPI schema first.
                    await api.delete(`api/organizations/${organizationId}/members/@me/`)

                    return null
                },
            },
        ],
    },
    reducers: {
        deleteUserModalOpen: [
            false,
            {
                setDeleteUserModalOpen: (_, { open }) => open,
            },
        ],
        organizationToDelete: [
            null as OrganizationBasicType | null,
            {
                setOrganizationToDelete: (_, { organization }) => organization,
            },
        ],
        isUserDeletionConfirmed: [
            false,
            {
                setIsUserDeletionConfirmed: (_, { confirmed }) => confirmed,
            },
        ],
    },
    selectors: {
        blockingOrganizations: [
            (s) => [s.user],
            (user: UserType | null): OrganizationBasicType[] => (user?.organizations ?? []).filter(isNotNil),
        ],
        hasPendingOrganizationDeletion: [
            (s) => [s.blockingOrganizations],
            (organizations: OrganizationBasicType[]): boolean =>
                organizations.some((organization) => organization.is_pending_deletion),
        ],
        deleteAccountDisabledReason: [
            (s) => [s.blockingOrganizations, s.hasPendingOrganizationDeletion, s.isUserDeletionConfirmed],
            (
                organizations: OrganizationBasicType[],
                hasPendingOrganizationDeletion: boolean,
                isUserDeletionConfirmed: boolean
            ): string | null => {
                if (hasPendingOrganizationDeletion) {
                    return 'Wait for your organization deletion to finish. This usually takes a few minutes.'
                }
                if (organizations.length > 0) {
                    return 'Leave or delete your remaining organizations first'
                }
                if (!isUserDeletionConfirmed) {
                    return `Type "${DELETE_CONFIRMATION_TEXT}" to confirm`
                }
                return null
            },
        ],
    },
    listeners: ({ actions, values }) => ({
        setDeleteUserModalOpen: ({ open }) => {
            if (open) {
                router.actions.replace(urls.settings('user-danger-zone'), { deletingUser: true })
                actions.pollPendingOrganizationDeletions()
            } else {
                router.actions.replace(urls.settings('user-danger-zone'))
            }
        },
        deleteOrganizationSuccess: () => {
            if (values.deleteUserModalOpen && values.organizationToDelete) {
                actions.setOrganizationToDelete(null)
                // The organization is only marked pending here, so the row stays until the server clears it.
                actions.loadUser()
                actions.pollPendingOrganizationDeletions()
            }
        },
        pollPendingOrganizationDeletions: async (_, breakpoint) => {
            await breakpoint(PENDING_DELETION_POLL_MS)
            if (!values.deleteUserModalOpen || !values.hasPendingOrganizationDeletion) {
                return
            }
            actions.loadUser()
            actions.pollPendingOrganizationDeletions()
        },
        leaveOrganizationSuccess: () => {
            router.actions.replace(urls.settings('user-danger-zone'), { deletingUser: true })

            lemonToast.success('Organization left successfully')

            window.location.reload()
        },
        leaveOrganizationFailure: () => {
            lemonToast.error('Failed to leave organization')
        },
    }),
    urlToAction: ({ actions, values }) => ({
        [urls.settings('user-danger-zone')]: (_, searchParams) => {
            const { deletingUser } = searchParams
            if (deletingUser && !values.deleteUserModalOpen) {
                actions.setDeleteUserModalOpen(true)
            }
        },
    }),
})
