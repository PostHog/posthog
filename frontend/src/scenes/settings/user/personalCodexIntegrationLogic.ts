export type personalCodexIntegrationLogicType = MakeLogicType<
    personalCodexIntegrationLogicValues,
    personalCodexIntegrationLogicActions
>

export const personalCodexIntegrationLogic = kea<personalCodexIntegrationLogicType>([
    path(['scenes', 'settings', 'user', 'personalCodexIntegrationLogic']),
    actions({
        openConnectModal: (opener: string) => ({ opener }),
        closeConnectModal: true,
        startDeviceLogin: true,
        pollDeviceLogin: true,
        finishDeviceLogin: (loginId: string) => ({ loginId }),
        setLogin: (login: UserCodexLoginApi | null) => ({ login }),
        setConnectError: (connectError: string | null) => ({ connectError }),
        connectCodexSuccess: (codexIntegration: UserCodexIntegrationApi) => ({ codexIntegration }),
    }),
    loaders(({ values }) => ({
        codexIntegration: [
            null as UserCodexIntegrationApi | null,
            {
                loadCodexIntegration: async () => {
                    const mutationCount = values.codexMutationCount
                    const integration = await usersIntegrationsCodexRetrieve('@me')
                    return values.codexMutationCount === mutationCount ? integration : values.codexIntegration
                },
                disconnectCodex: async (): Promise<UserCodexIntegrationApi> => {
                    await usersIntegrationsCodexDestroy('@me')
                    return { status: CodexIntegrationStatusEnumApi.NotConnected }
                },
            },
        ],
    })),
    reducers({
        codexIntegration: {
            connectCodexSuccess: (_, { codexIntegration }) => codexIntegration,
        },
        codexMutationCount: [
            0,
            {
                startDeviceLogin: (count) => count + 1,
                connectCodexSuccess: (count) => count + 1,
                disconnectCodex: (count) => count + 1,
            },
        ],
        connectModalOpener: [
            null as string | null,
            {
                openConnectModal: (_, { opener }) => opener,
                closeConnectModal: () => null,
            },
        ],
        login: [null as UserCodexLoginApi | null, { setLogin: (_, { login }) => login }],
        connectError: [
            null as string | null,
            {
                setConnectError: (_, { connectError }) => connectError,
                startDeviceLogin: () => null,
                openConnectModal: () => null,
            },
        ],
        connecting: [
            false,
            {
                startDeviceLogin: () => true,
                closeConnectModal: () => false,
                setConnectError: () => false,
            },
        ],
        codexIntegrationLoadFailed: [
            false,
            {
                loadCodexIntegrationFailure: () => true,
                loadCodexIntegrationSuccess: () => false,
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openConnectModal: ({ opener }) => {
            posthog.capture('personal integration connect clicked', {
                integration_kind: 'codex',
                surface: opener.split(':')[0],
            })
            actions.startDeviceLogin()
        },
        startDeviceLogin: async () => {
            const loginId = uuid()
            cache.disposables.dispose('codexLogin')
            actions.setLogin({ login_id: loginId, status: 'starting', user_code: null })
            try {
                const login = await usersIntegrationsCodexLoginCreate('@me', { login_id: loginId })
                if (cache.disposables.isDisposed || values.login?.login_id !== loginId) {
                    await usersIntegrationsCodexLoginDestroy('@me', loginId)
                    return
                }
                actions.setLogin(login)
                cache.disposables.add(() => {
                    const controller = new AbortController()
                    cache.loginAbortController = controller
                    const timer = window.setInterval(() => actions.pollDeviceLogin(), 2000)
                    return () => {
                        window.clearInterval(timer)
                        controller.abort()
                    }
                }, 'codexLogin')
                actions.pollDeviceLogin()
            } catch {
                if (!cache.disposables.isDisposed && values.login?.login_id === loginId) {
                    actions.setConnectError('Could not start the ChatGPT login. Try again.')
                }
            }
        },
        pollDeviceLogin: async () => {
            const loginId = values.login?.login_id
            if (!loginId || cache.pollingLoginId === loginId) {
                return
            }
            cache.pollingLoginId = loginId
            const signal = cache.loginAbortController?.signal
            try {
                const login = await retryWithBackoff(
                    () => usersIntegrationsCodexLoginRetrieve('@me', loginId, { signal }),
                    {
                        signal,
                        maxAttempts: 5,
                        initialDelayMs: 2000,
                        backoffMultiplier: 2,
                        shouldRetry: (error) =>
                            error instanceof NetworkError || (error instanceof ApiError && (error.status ?? 0) >= 500),
                    }
                )
                if (signal?.aborted || cache.disposables.isDisposed || values.login?.login_id !== loginId) {
                    return
                }
                actions.setLogin(login)
                if (login.status === 'connected') {
                    actions.finishDeviceLogin(loginId)
                } else if (['failed', 'expired', 'canceled'].includes(login.status)) {
                    cache.disposables.dispose('codexLogin')
                    actions.setConnectError(
                        login.status === 'expired'
                            ? 'This device code expired. Try again to get a new code.'
                            : 'The ChatGPT login did not complete. Try again.'
                    )
                }
            } catch {
                if (!signal?.aborted && !cache.disposables.isDisposed && values.login?.login_id === loginId) {
                    cache.disposables.dispose('codexLogin')
                    actions.setConnectError('Could not check the ChatGPT login. Try again.')
                }
            } finally {
                if (cache.pollingLoginId === loginId) {
                    cache.pollingLoginId = null
                }
            }
        },
        finishDeviceLogin: async ({ loginId }, breakpoint) => {
            cache.disposables.dispose('codexLogin')
            try {
                const integration = await usersIntegrationsCodexRetrieve('@me')
                breakpoint()
                if (cache.disposables.isDisposed || values.login?.login_id !== loginId) {
                    return
                }
                if (integration.status !== 'connected') {
                    actions.setConnectError('The account is no longer connected. Try again.')
                    return
                }
                actions.connectCodexSuccess(integration)
                actions.closeConnectModal()
                lemonToast.success('Codex connected')
            } catch {
                breakpoint()
                if (!cache.disposables.isDisposed && values.login?.login_id === loginId) {
                    actions.setConnectError('Could not check the connected account. Try again.')
                }
            }
        },
        closeConnectModal: async () => {
            cache.disposables.dispose('codexLogin')
            const login = values.login
            actions.setLogin(null)
            if (login && login.status !== 'connected') {
                await usersIntegrationsCodexLoginDestroy('@me', login.login_id).catch(() => undefined)
            }
        },
        disconnectCodexSuccess: () => {
            lemonToast.success('Codex disconnected')
        },
        disconnectCodexFailure: () => {
            lemonToast.error('Could not disconnect Codex. Try again.')
        },
    })),
    events(({ actions, cache }) => ({
        afterMount: () => {
            actions.loadCodexIntegration()
            cache.disposables.add(
                () => {
                    const onFocus = (): void => actions.loadCodexIntegration()
                    window.addEventListener('focus', onFocus)
                    return () => window.removeEventListener('focus', onFocus)
                },
                'focusRefetch',
                { pauseOnPageHidden: false }
            )
        },
    })),
])
