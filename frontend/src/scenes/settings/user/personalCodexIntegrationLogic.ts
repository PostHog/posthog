import { MakeLogicType, actions, events, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import {
    usersIntegrationsCodexCreate,
    usersIntegrationsCodexDestroy,
    usersIntegrationsCodexRetrieve,
} from '~/generated/core/api'
import {
    CodexIntegrationStatusEnumApi,
    type UserCodexAuthTokensApi,
    type UserCodexIntegrationApi,
} from '~/generated/core/api.schemas'

import { parseCodexAuthFile } from './codexAuthFile'
import { type CodexLoginPlatform, browserCodexLoginPlatform } from './codexLoginCommands'

const CONNECT_ERROR_FALLBACK = 'Could not connect Codex. Run the command again, then paste the new sign-in.'
const CLIPBOARD_BLOCKED_ERROR = 'Your browser blocked clipboard access. Click the field and paste with your keyboard.'

async function clearClipboard(): Promise<void> {
    try {
        await navigator.clipboard.writeText('')
    } catch {
        lemonToast.warning('Could not clear your clipboard. Copy something else to remove the sign-in from it.')
    }
}

function describeConnectError(error: unknown): string {
    const detail = error && typeof error === 'object' ? (error as { detail?: unknown }).detail : undefined
    return typeof detail === 'string' && detail ? detail : CONNECT_ERROR_FALLBACK
}

