import { MakeLogicType, actions, events, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'
import { v4 as uuid } from 'uuid'

import { ApiError, NetworkError } from 'lib/api-error'
import { lemonToast } from 'lib/lemon-ui/LemonToast'
import { retryWithBackoff } from 'lib/utils/async'

import {
    usersIntegrationsCodexDestroy,
    usersIntegrationsCodexRetrieve,
    usersIntegrationsCodexLoginCreate,
    usersIntegrationsCodexLoginRetrieve,
    usersIntegrationsCodexLoginDestroy,
} from '~/generated/core/api'
import {
    CodexIntegrationStatusEnumApi,
    type UserCodexIntegrationApi,
    type UserCodexLoginApi,
} from '~/generated/core/api.schemas'

