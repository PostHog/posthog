// Keeps the embedded SQL editor and the form's `hogql_query` in step, and gives the editor the
// interval placeholders with preview values for the export's schedule.
export const batchExportHogQLQueryLogic: LogicWrapper<batchExportHogQLQueryLogicType> =
    kea<batchExportHogQLQueryLogicType>([
        props({ id: null, service: null } as BatchExportConfigFormLogicProps),
        key(({ service, id }: BatchExportConfigFormLogicProps) => (id ? `ID:${id}` : `NEW:${service}`)),
        path((key) => ['scenes', 'data-pipelines', 'batch-exports', 'batchExportHogQLQueryLogic', key]),
        connect((props: BatchExportConfigFormLogicProps) => ({
            values: [
                batchExportConfigFormLogic(props),
                ['configuration'],
                teamLogic,
                ['timezone as projectTimezone'],
                sqlEditorLogic({ tabId: batchExportHogQLEditorTabId(props), mode: SQLEditorMode.Embedded }),
                ['queryInput'],
            ],
            actions: [
                batchExportConfigFormLogic(props),
                [
                    'setConfigurationValue',
                    'setConfigurationValues',
                    'resetConfiguration',
                    'loadBatchExportConfigSuccess',
                    'updateBatchExportConfigSuccess',
                ],
                sqlEditorLogic({ tabId: batchExportHogQLEditorTabId(props), mode: SQLEditorMode.Embedded }),
                ['setQueryInput', 'setSourceQuery', 'setPlaceholders'],
            ],
        })),
        selectors({
            scheduleInterval: [
                (s) => [s.configuration],
                (configuration: Record<string, any>): BatchExportInterval => configuration.interval ?? 'hour',
            ],
            scheduleTimezone: [
                (s) => [s.configuration],
                (configuration: Record<string, any>): string | null => configuration.timezone ?? null,
            ],
            scheduleOffsetDay: [
                (s) => [s.configuration],
                (configuration: Record<string, any>): number | null => configuration.offset_day ?? null,
            ],
            scheduleOffsetHour: [
                (s) => [s.configuration],
                (configuration: Record<string, any>): number | null => configuration.offset_hour ?? null,
            ],
            previewInterval: [
                (s) => [
                    s.scheduleInterval,
                    s.scheduleTimezone,
                    s.scheduleOffsetDay,
                    s.scheduleOffsetHour,
                    s.projectTimezone,
                ],
                (
                    interval: BatchExportInterval,
                    scheduleTimezone: string | null,
                    offsetDay: number | null,
                    offsetHour: number | null,
                    projectTimezone: string
                ): BatchExportDataInterval => {
                    const scheduleUsesTimezone = interval === 'day' || interval === 'week'
                    return lastCompleteDataInterval({
                        interval,
                        now: dayjs(),
                        timezone: scheduleUsesTimezone ? scheduleTimezone || projectTimezone : 'UTC',
                        offsetDay,
                        offsetHour,
                    })
                },
            ],
            // HogQL reads these strings as times in the project timezone, so convert the bounds to it first.
            previewStart: [
                (s) => [s.previewInterval, s.projectTimezone],
                (previewInterval: BatchExportDataInterval, projectTimezone: string): string =>
                    previewInterval.start.tz(projectTimezone).format(PLACEHOLDER_VALUE_FORMAT),
            ],
            previewEnd: [
                (s) => [s.previewInterval, s.projectTimezone],
                (previewInterval: BatchExportDataInterval, projectTimezone: string): string =>
                    previewInterval.end.tz(projectTimezone).format(PLACEHOLDER_VALUE_FORMAT),
            ],
            placeholders: [
                (s) => [s.previewStart, s.previewEnd],
                (previewStart: string, previewEnd: string): SQLEditorPlaceholder[] => [
                    {
                        name: DATA_INTERVAL_START_PLACEHOLDER,
                        description: 'Start of the time range a run exports. Rows at or after this time are included.',
                        previewValue: previewStart,
                    },
                    {
                        name: DATA_INTERVAL_END_PLACEHOLDER,
                        description: 'End of the time range a run exports. Rows before this time are included.',
                        previewValue: previewEnd,
                    },
                ],
            ],
            usesIntervalPlaceholders: [
                (s) => [s.queryInput],
                (queryInput: string | null): boolean =>
                    queryInput === null ||
                    queryUsesPlaceholder(queryInput, DATA_INTERVAL_START_PLACEHOLDER) ||
                    queryUsesPlaceholder(queryInput, DATA_INTERVAL_END_PLACEHOLDER),
            ],
        }),
        sharedListeners(({ actions, values }) => ({
            syncFormToEditor: () => {
                const formQuery: string = values.configuration.hogql_query ?? ''
                // An empty form query means the config has not loaded yet, so keep what the editor has
                if (values.queryInput !== null && formQuery && formQuery !== values.queryInput) {
                    actions.setQueryInput(formQuery)
                }
            },
        })),
        listeners(({ actions, values, sharedListeners }) => ({
            setQueryInput: ({ queryInput }) => {
                if (queryInput !== null && queryInput !== values.configuration.hogql_query) {
                    actions.setConfigurationValue('hogql_query', queryInput)
                }
            },
            // Each listener writes only when the two sides differ, so a write settles instead of bouncing back
            resetConfiguration: sharedListeners.syncFormToEditor,
            setConfigurationValues: sharedListeners.syncFormToEditor,
            loadBatchExportConfigSuccess: sharedListeners.syncFormToEditor,
            updateBatchExportConfigSuccess: sharedListeners.syncFormToEditor,
        })),
        subscriptions(({ actions }) => ({
            placeholders: (placeholders: SQLEditorPlaceholder[]) => actions.setPlaceholders(placeholders),
        })),
        afterMount(({ actions, values }) => {
            if (values.queryInput !== null) {
                return
            }
            const initialQuery = values.configuration.hogql_query || DEFAULT_HOGQL_QUERY
            actions.setQueryInput(initialQuery)
            actions.setSourceQuery({
                kind: NodeKind.DataVisualizationNode,
                source: { kind: NodeKind.HogQLQuery, query: initialQuery },
                display: ChartDisplayType.ActionsTable,
            })
        }),
    ])
