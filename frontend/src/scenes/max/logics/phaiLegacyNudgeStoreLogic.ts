import { MakeLogicType, actions, kea, path, reducers } from 'kea'

import { permanentlyMount } from 'lib/utils/kea-logic-builders'

import { PHAI_LEGACY_NUDGE_DISMISSED_KEY, PHAI_LEGACY_NUDGE_IMPRESSIONS_KEY } from '../max-storage-keys'

/**
 * Device-wide state for the "switch to the new PostHog AI" notice, kept out of `phaiLegacyNudgeLogic` because
 * that one is keyed per panel: the `/ai` scene and the side panel can be mounted at once, and they must share
 * one dismissal and one impression count rather than each getting their own.
 *
 * Temporary migration affordance - delete alongside `scenes/max` once everyone is on the new PostHog AI.
 */

/** How many times the notice may be shown before it retires itself instead of costing panel height forever. */
export const PHAI_LEGACY_NUDGE_IMPRESSION_BUDGET = 3

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface phaiLegacyNudgeStoreLogicValues {
    dismissed: boolean
    impressionCount: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface phaiLegacyNudgeStoreLogicActions {
    markDismissed: () => {
        value: true
    }
    markShown: () => {
        value: true
    }
}

export type phaiLegacyNudgeStoreLogicType = MakeLogicType<
    phaiLegacyNudgeStoreLogicValues,
    phaiLegacyNudgeStoreLogicActions
>

export const phaiLegacyNudgeStoreLogic = kea<phaiLegacyNudgeStoreLogicType>([
    path(['scenes', 'max', 'logics', 'phaiLegacyNudgeStoreLogic']),

    actions({
        markShown: true,
        markDismissed: true,
    }),

    reducers({
        dismissed: [
            false,
            { persist: true, storageKey: PHAI_LEGACY_NUDGE_DISMISSED_KEY },
            {
                markDismissed: () => true,
            },
        ],
        impressionCount: [
            0,
            { persist: true, storageKey: PHAI_LEGACY_NUDGE_IMPRESSIONS_KEY },
            {
                markShown: (state) => state + 1,
            },
        ],
    }),

    permanentlyMount(),
])
