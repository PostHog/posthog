import { MakeLogicType, actions, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { router } from 'kea-router'
import { subscriptions } from 'kea-subscriptions'
import posthog from 'posthog-js'

import { urls } from 'scenes/urls'

import { HumanMessage } from '~/queries/schema/schema-assistant-messages'

import { PhaiViewMode, maxGlobalLogic } from '../maxGlobalLogic'
import type { ThreadMessage } from '../maxThreadLogic'
import { isHumanMessage } from '../utils'
import { phaiLegacyNudgeStoreLogic } from './phaiLegacyNudgeStoreLogic'

/**
 * Decides whether to offer a user who switched back to the legacy chat a route into the new PostHog AI, and
 * carries their current question across when they take it.
 *
 * The thread state arrives as props rather than via `connect` because `maxThreadLogic` is keyed and bound by
 * the host - same arrangement as `maxWebAnalyticsNudgeLogic`. Keyed on `panelId` so the `/ai` scene and the
 * side panel, which can be open on different conversations at once, don't read each other's question.
 *
 * Temporary migration affordance - delete alongside `scenes/max` once everyone is on the new PostHog AI.
 */

/** Why someone went back to the legacy chat. Values are pinned: they are analytics property values. */
export type PhaiLegacyNudgeReason = 'too_slow' | 'missing_chats' | 'broke' | 'worse_answers' | 'other'

export interface PhaiLegacyNudgeLogicProps {
    panelId: string
    threadGrouped: ThreadMessage[]
    streamingActive: boolean
    isSharedThread: boolean
    conversationId: string | null
}

export interface PhaiLegacyNudgeReportProperties {
    conversation_id: string | null
    has_question: boolean
}

/**
 * Caps what one free-text answer can carry into an event property. Long enough for a sentence, short enough
 * that nobody pastes a conversation into it.
 */
export const OTHER_REASON_MAX_LENGTH = 200

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface phaiLegacyNudgeLogicValues {
    effectivePhaiView: PhaiViewMode // maxGlobalLogic
    isPhaiSandboxFlagOn: boolean // maxGlobalLogic
    dismissed: boolean // phaiLegacyNudgeStoreLogic
    lastHumanQuestion: string | null
    shownThisMount: boolean
    reasonPromptVisible: boolean
    otherReasonSelected: boolean
    otherReasonText: string
    reportProperties: PhaiLegacyNudgeReportProperties
    shouldShow: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface phaiLegacyNudgeLogicActions {
    setPhaiViewMode: (mode: PhaiViewMode) => {
        mode: PhaiViewMode
    } // maxGlobalLogic
    markDismissed: () => {
        value: true
    } // phaiLegacyNudgeStoreLogic
    closeReasonPrompt: () => {
        value: true
    }
    evaluateReporting: () => {
        value: true
    }
    markShownThisMount: () => {
        value: true
    }
    nudgeClicked: () => {
        value: true
    }
    nudgeDismissed: () => {
        value: true
    }
    submitReason: (reason: PhaiLegacyNudgeReason) => {
        reason: PhaiLegacyNudgeReason
    }
    selectOtherReason: () => {
        value: true
    }
    setOtherReasonText: (text: string) => {
        text: string
    }
    submitOtherReason: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface phaiLegacyNudgeLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        lastHumanQuestion: (threadGrouped: ThreadMessage[]) => string | null
        shouldShow: (
            effectivePhaiView: PhaiViewMode,
            isPhaiSandboxFlagOn: boolean,
            dismissed: boolean,
            streamingActive: boolean,
            isSharedThread: boolean
        ) => boolean
        reportProperties: (
            lastHumanQuestion: string | null,
            conversationId: string | null
        ) => PhaiLegacyNudgeReportProperties
    }
}

export type phaiLegacyNudgeLogicType = MakeLogicType<
    phaiLegacyNudgeLogicValues,
    phaiLegacyNudgeLogicActions,
    PhaiLegacyNudgeLogicProps,
    phaiLegacyNudgeLogicMeta
>

export const phaiLegacyNudgeLogic = kea<phaiLegacyNudgeLogicType>([
    path(['scenes', 'max', 'logics', 'phaiLegacyNudgeLogic']),
    props({} as PhaiLegacyNudgeLogicProps),
    key((props) => props.panelId),

    connect(() => ({
        values: [
            maxGlobalLogic,
            ['effectivePhaiView', 'isPhaiSandboxFlagOn'],
            phaiLegacyNudgeStoreLogic,
            ['dismissed'],
        ],
        actions: [maxGlobalLogic, ['setPhaiViewMode'], phaiLegacyNudgeStoreLogic, ['markDismissed']],
    })),

    actions({
        nudgeClicked: true,
        nudgeDismissed: true,
        submitReason: (reason: PhaiLegacyNudgeReason) => ({ reason }),
        selectOtherReason: true,
        setOtherReasonText: (text: string) => ({ text }),
        submitOtherReason: true,
        closeReasonPrompt: true,
        evaluateReporting: true,
        markShownThisMount: true,
    }),

    reducers({
        // Guards the analytics event only, so one mount reports one impression however many times the
        // eligibility selectors re-evaluate. It does not gate whether the notice renders.
        shownThisMount: [
            false,
            {
                markShownThisMount: () => true,
            },
        ],
        reasonPromptVisible: [
            false,
            {
                nudgeDismissed: () => true,
                submitReason: () => false,
                submitOtherReason: () => false,
                closeReasonPrompt: () => false,
            },
        ],
        // "Other" swaps the fixed answers for the text field rather than answering, so the prompt stays open
        // until the user sends something or closes it.
        otherReasonSelected: [
            false,
            {
                selectOtherReason: () => true,
                nudgeDismissed: () => false,
                submitOtherReason: () => false,
                closeReasonPrompt: () => false,
            },
        ],
        // Not cleared on `submitOtherReason`: reducers run before listeners, so clearing it there would empty
        // the answer before the listener reports it. The prompt closes on submit, so a stale value never shows.
        otherReasonText: [
            '',
            {
                setOtherReasonText: (_, { text }) => text,
                nudgeDismissed: () => '',
                closeReasonPrompt: () => '',
            },
        ],
    }),

    selectors({
        lastHumanQuestion: [
            (_s, p) => [p.threadGrouped],
            (threadGrouped: ThreadMessage[]): string | null =>
                (threadGrouped.filter(isHumanMessage).pop() as HumanMessage | undefined)?.content ?? null,
        ],
        shouldShow: [
            (s, p) => [s.effectivePhaiView, s.isPhaiSandboxFlagOn, s.dismissed, p.streamingActive, p.isSharedThread],
            (
                effectivePhaiView: PhaiViewMode,
                isPhaiSandboxFlagOn: boolean,
                dismissed: boolean,
                streamingActive: boolean,
                isSharedThread: boolean
            ): boolean =>
                effectivePhaiView === 'legacy' &&
                // Without the flag there is nothing to switch to, so the notice would be a dead end.
                isPhaiSandboxFlagOn &&
                !dismissed &&
                !streamingActive &&
                !isSharedThread,
        ],
        reportProperties: [
            (s, p) => [s.lastHumanQuestion, p.conversationId],
            (lastHumanQuestion: string | null, conversationId: string | null): PhaiLegacyNudgeReportProperties => ({
                conversation_id: conversationId,
                has_question: !!lastHumanQuestion,
            }),
        ],
    }),

    listeners(({ values, actions }) => ({
        nudgeClicked: () => {
            posthog.capture('posthog ai legacy nudge clicked', values.reportProperties)
            actions.setPhaiViewMode('new')
            // `/ai?ask=` seeds the new composer and submits it once AI consent is granted, so the question the
            // legacy chat just answered is what the new surface actually runs. See `phaiAiComposerSeedLogic`.
            router.actions.push(urls.ai(undefined, values.lastHumanQuestion ?? undefined))
        },
        nudgeDismissed: () => {
            posthog.capture('posthog ai legacy nudge dismissed', values.reportProperties)
            actions.markDismissed()
        },
        submitReason: ({ reason }) => {
            posthog.capture('posthog ai legacy nudge reason', { ...values.reportProperties, reason })
        },
        submitOtherReason: () => {
            const text = values.otherReasonText.trim()
            if (!text) {
                return
            }
            posthog.capture('posthog ai legacy nudge reason', {
                ...values.reportProperties,
                reason: 'other',
                reason_text: text,
            })
        },
        evaluateReporting: () => {
            if (values.shouldShow && !values.shownThisMount) {
                actions.markShownThisMount()
                posthog.capture('posthog ai legacy nudge shown', values.reportProperties)
            }
        },
    })),

    subscriptions(({ actions }) => ({
        shouldShow: () => actions.evaluateReporting(),
    })),

    afterMount(({ actions }) => {
        actions.evaluateReporting()
    }),
])
