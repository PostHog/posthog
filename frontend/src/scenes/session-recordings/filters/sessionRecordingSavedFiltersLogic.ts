export const sessionRecordingSavedFiltersLogic = kea<sessionRecordingSavedFiltersLogicType>([
    path(() => ['scenes', 'session-recordings', 'filters', 'sessionRecordingSavedFiltersLogic']),
    connect(() => ({
        values: [
            playlistFiltersLogic,
            ['isFiltersExpanded'],
            playerSettingsLogic,
            ['replayLayout'],
            teamLogic,
            ['currentProjectId'],
        ],
        actions: [playlistFiltersLogic, ['setIsFiltersExpanded']],
    })),
    actions(() => ({
        setSavedPlaylistsFilters: (filters: Partial<SavedSessionRecordingPlaylistsFilters>) => ({
            filters,
        }),
        loadSavedFiltersIfNeeded: true,
        loadSavedFilters: true,
        updatePlaylist: (
            shortId: SessionRecordingPlaylistType['short_id'],
            properties: Partial<SessionRecordingPlaylistType>
        ) => ({ shortId, properties }),
        deletePlaylist: (playlist: SessionRecordingPlaylistType) => ({ playlist }),
        checkForSavedFilterRedirect: true,
        setAppliedSavedFilter: (appliedSavedFilter: SessionRecordingPlaylistType | null) => ({ appliedSavedFilter }),
        requestApplySavedFilter: (filter: SessionRecordingPlaylistType) => ({ filter }),
        clearPendingFilterApplication: true,
    })),
    reducers(() => ({
        filters: [
            DEFAULT_PLAYLIST_FILTERS as SavedSessionRecordingPlaylistsFilters | Record<string, any>,
            {
                setSavedPlaylistsFilters: (state, { filters }) =>
                    objectClean({
                        ...Object.fromEntries(Object.entries(state || {}).filter(([key]) => key in filters)),
                        ...filters,
                        ...('page' in filters ? {} : { page: 1 }),
                    }),
            },
        ],
        appliedSavedFilter: [
            null as SessionRecordingPlaylistType | null,
            {
                setAppliedSavedFilter: (_, { appliedSavedFilter }) => appliedSavedFilter,
            },
        ],
        pendingFilterApplication: [
            null as SessionRecordingPlaylistType | null,
            {
                requestApplySavedFilter: (_, { filter }) => filter,
                clearPendingFilterApplication: () => null,
            },
        ],
        loadSavedFiltersFailed: [
            false,
            {
                loadSavedFilters: () => false,
                loadSavedFiltersSuccess: () => false,
                loadSavedFiltersFailure: () => true,
            },
        ],
        hasLoadedSavedFilters: [
            false,
            {
                loadSavedFiltersSuccess: () => true,
            },
        ],
    })),
    loaders(({ values, actions }) => ({
        savedFilters: {
            __default: { results: [], count: 0, filters: null } as SavedSessionRecordingPlaylistsResult,
            loadSavedFilters: async (_, breakpoint) => {
                const filters = { ...values.filters }

                const params = {
                    limit: PLAYLISTS_PER_PAGE,
                    offset: Math.max(0, (filters.page - 1) * PLAYLISTS_PER_PAGE),
                    order: '-last_modified_at',
                    created_by: filters.createdBy && filters.createdBy !== 'All users' ? filters.createdBy : undefined,
                    search: filters.search || undefined,
                    date_from: undefined,
                    date_to: undefined,
                    pinned: undefined,
                    type: 'filters',
                }

                const response = await api.recordings.listPlaylists(toParams(params))
                breakpoint()

                return response
            },
        },
        playlists: {
            __default: { results: [], count: 0, filters: null } as SavedSessionRecordingPlaylistsResult,
            updatePlaylist: async ({ shortId, properties }, breakpoint) => {
                await breakpoint(100)
                const updatedPlaylist = await api.recordings.updatePlaylist(shortId, properties)
                breakpoint()

                const index = values.playlists.results.findIndex((x) => x.short_id === updatedPlaylist.short_id)
                if (index > -1) {
                    values.playlists.results[index] = updatedPlaylist
                }

                return { ...values.playlists, results: [...values.playlists.results] }
            },
            deletePlaylist: async ({ playlist }) => {
                const wasApplied = values.appliedSavedFilter?.short_id === playlist.short_id
                await deletePlaylist(playlist, (undo) => {
                    if (wasApplied) {
                        actions.setAppliedSavedFilter(undo ? playlist : null)
                    }
                    actions.loadSavedFilters()
                })
                values.playlists.results = values.playlists.results.filter((x) => x.short_id !== playlist.short_id)
                actions.loadSavedFilters()
                return values.playlists
            },
        },
    })),
    listeners(({ actions, values, cache }) => ({
        setIsFiltersExpanded: ({ isFiltersExpanded }) => {
            if (isFiltersExpanded) {
                actions.loadSavedFiltersIfNeeded()
            }
        },
        loadSavedFiltersSuccess: ({ savedFilters }) => {
            const applied = values.appliedSavedFilter
            const fresh = applied && savedFilters.results.find((f) => f.short_id === applied.short_id)
            if (fresh && fresh !== applied) {
                actions.setAppliedSavedFilter(fresh)
            }
        },
        loadSavedFiltersIfNeeded: () => {
            if (!values.hasLoadedSavedFilters && !values.savedFiltersLoading) {
                actions.loadSavedFilters()
            }
        },
        setSavedPlaylistsFilters: () => {
            actions.loadSavedFilters()
        },
        checkForSavedFilterRedirect: async () => {
            //If you want to load a saved filter via GET param, you can do it like this: ?savedFilterId=bndnfkxL
            const { savedFilterId, filters } = router.values.searchParams
            // The list rewrites the URL while the fetch is out.
            if (savedFilterId && cache.loadingSavedFilterId !== savedFilterId) {
                cache.loadingSavedFilterId = savedFilterId
                // Capture the route before the fetch. The load can resolve after the user has already
                // navigated elsewhere (e.g. to Replay vision) - only redirect if they are still here.
                const pathnameBeforeLoad = removeProjectIdIfPresent(router.values.location.pathname)
                const savedFilter = (await sessionRecordingPlaylistsRetrieve(
                    String(values.currentProjectId),
                    savedFilterId
                ).finally(() => {
                    cache.loadingSavedFilterId = null
                })) as unknown as SessionRecordingPlaylistType
                if (savedFilter && removeProjectIdIfPresent(router.values.location.pathname) === pathnameBeforeLoad) {
                    if (!filters) {
                        router.actions.push(
                            urls.replay(ReplayTabs.Home, stripSessionIds(asUniversalFilters(savedFilter.filters)))
                        )
                    }
                    actions.setAppliedSavedFilter(savedFilter)
                }
            }
        },
    })),

    actionToUrl(({ values }) => ({
        setAppliedSavedFilter: ({ appliedSavedFilter }) => {
            const { pathname, searchParams, hashParams } = router.values.currentLocation
            const savedFilterId = appliedSavedFilter?.short_id
            if (
                !isNewReplayLayout(values.replayLayout) ||
                removeProjectIdIfPresent(pathname) !== urls.replay(ReplayTabs.Home) ||
                searchParams.savedFilterId === savedFilterId
            ) {
                return
            }
            return [pathname, { ...searchParams, savedFilterId }, hashParams, { replace: true }]
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.replay(ReplayTabs.Home)]: (_, { savedFilterId }) => {
            if (savedFilterId && savedFilterId !== values.appliedSavedFilter?.short_id) {
                actions.checkForSavedFilterRedirect()
            }
        },
    })),
    selectors(({ actions }) => ({
        appliedSavedFilterFilters: [
            (s) => [s.appliedSavedFilter],
            (appliedSavedFilter: SessionRecordingPlaylistType | null): RecordingUniversalFilters | null => {
                const universal = appliedSavedFilter ? asUniversalFilters(appliedSavedFilter.filters) : undefined
                return universal ? comparableRecordingFilters({ ...getDefaultFilters(), ...universal }) : null
            },
        ],
        paginationSavedFilters: [
            (s) => [s.filters, s.savedFilters],
            (
                filters: Record<string, any> | SavedSessionRecordingPlaylistsFilters,
                savedFilters: SavedSessionRecordingPlaylistsResult
            ): PaginationManual => {
                return {
                    controlled: true,
                    pageSize: PLAYLISTS_PER_PAGE,
                    currentPage: filters.page,
                    entryCount: savedFilters.count,
                    onBackward: savedFilters.previous
                        ? () => {
                              actions.setSavedPlaylistsFilters({
                                  page: filters.page - 1,
                              })
                              actions.loadSavedFilters()
                          }
                        : undefined,
                    onForward: savedFilters.next
                        ? () => {
                              actions.setSavedPlaylistsFilters({
                                  page: filters.page + 1,
                              })
                              actions.loadSavedFilters()
                          }
                        : undefined,
                }
            },
        ],
    })),
    afterMount(({ actions, values }) => {
        if (values.isFiltersExpanded) {
            actions.loadSavedFiltersIfNeeded()
        }
    }),
])
