export const SCENE_PLAYLIST_LOGIC_PROPS: SessionRecordingPlaylistLogicProps = {
    logicKey: 'scene',
    updateSearchParams: true,
}

export function replayUrlPointsSomewhere(searchParams: Record<string, any>, hashParams: Record<string, any>): boolean {
    return Object.keys(searchParams).length > 0 || Boolean(hashParams.sessionRecordingId)
}

export const humanFriendlyTabName = (tab: ReplayTabs): string => {
    switch (tab) {
        case ReplayTabs.Home:
            return 'Recordings'
        case ReplayTabs.Playlists:
            return 'Collections'
        case ReplayTabs.Settings:
            return 'Settings'
        default:
            return capitalizeFirstLetter(tab)
    }
}

