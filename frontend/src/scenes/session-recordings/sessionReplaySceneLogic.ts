export const sessionReplaySceneLogic = kea<sessionReplaySceneLogicType>([
    path(() => ['scenes', 'session-recordings', 'sessionReplaySceneLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], aiConsentLogic, ['dataProcessingAccepted']],
    })),
    actions({
        setTab: (tab: ReplayTabs = ReplayTabs.Home) => ({ tab }),
        setPickSeekSessionId: (sessionId: string | null) => ({ sessionId }),
    }),
    reducers(() => ({
        tab: [
            ReplayTabs.Home as ReplayTabs,
            {
                setTab: (_, { tab }) => tab,
            },
        ],
        pickSeekSessionId: [
            null as string | null,
            {
                setPickSeekSessionId: (_, { sessionId }) => sessionId,
            },
        ],
    })),

    listeners(({ actions, values }) => ({
        [sessionRecordingsPlaylistLogic(SCENE_PLAYLIST_LOGIC_PROPS).actionTypes.setSelectedRecordingId]: ({
            id,
        }: {
            id: string | null
        }) => {
            if (!values.pickSeekSessionId || id === values.pickSeekSessionId) {
                return
            }
            actions.setPickSeekSessionId(null)
            const { location, searchParams, hashParams } = router.values
            if (searchParams.t === undefined) {
                return
            }
            const nextParams = { ...searchParams }
            delete nextParams.t
            router.actions.replace(location.pathname, nextParams, hashParams)
        },
    })),

    trackedActionToUrl(({ values }) => {
        return {
            setTab: () => [urls.replay(values.tab), router.values.searchParams, router.values.hashParams],
        }
    }),

    selectors(() => ({
        picksInList: [
            (s) => [s.featureFlags, s.dataProcessingAccepted],
            (featureFlags: FeatureFlagsSet, dataProcessingAccepted: boolean): boolean =>
                dataProcessingAccepted &&
                featureFlags[FEATURE_FLAGS.REPLAY_UI_REDESIGN_2026] !== 'test' &&
                picksInListFromFlag(featureFlags[FEATURE_FLAGS.REPLAY_VISION_WATCH_IN_LIST_EXPERIMENT]),
        ],
        breadcrumbs: [
            (s) => [s.tab],
            (tab: ReplayTabs): Breadcrumb[] => {
                const breadcrumbs: Breadcrumb[] = []
                if (tab !== ReplayTabs.Home) {
                    breadcrumbs.push({
                        key: Scene.Replay,
                        name: 'Replay',
                        path: urls.replay(),
                        iconType: sceneConfigurations[Scene.Replay].iconType || 'default_icon_type',
                    })
                }
                breadcrumbs.push({
                    key: tab,
                    name: humanFriendlyTabName(tab),
                    iconType: sceneConfigurations[Scene.Replay].iconType || 'default_icon_type',
                })

                return breadcrumbs
            },
        ],
        [SIDE_PANEL_CONTEXT_KEY]: [
            () => [router.selectors.searchParams],
            (searchParams: Record<string, any>): SidePanelSceneContext => {
                return searchParams.sessionRecordingId
                    ? {
                          activity_scope: ActivityScope.REPLAY,
                          activity_item_id: searchParams.sessionRecordingId,
                      }
                    : {
                          activity_scope: ActivityScope.REPLAY,
                      }
            },
        ],
    })),

    urlToAction(({ actions, values }) => {
        return {
            '/replay/:tab': ({ tab }) => {
                // we saw a page get stuck in a redirect loop between recent and home
                // so, we're extra careful that the value being set is a valid tab
                const candidateTab = tab as ReplayTabs
                const validTab = Object.values(ReplayTabs).includes(candidateTab) ? candidateTab : ReplayTabs.Home
                if (validTab !== values.tab) {
                    actions.setTab(validTab)
                }
            },
        }
    }),
])
