const TWENTY_FOUR_HOURS_IN_MS = 24 * 60 * 60 * 1000 // +- before and after start and end of a recording to query for session linked events.
const FIVE_MINUTES_IN_MS = 5 * 60 * 1000 // +- before and after start and end of a recording to query for events related by person.
const TAGS = { scene: 'ReplaySingle', productKey: 'session_replay' }
// loadEvents reads each row's columns by position. Each flag_evaluations read selects the columns of the events read it pairs with.
const SESSION_EVENT_COLUMNS = hogql.raw(
    'uuid, event, timestamp, elements_chain, properties.$window_id, properties.$current_url, properties.$event_type, properties.$viewport_width, properties.$viewport_height, properties.$screen_name, distinct_id'
)
const RELATED_EVENT_COLUMNS = hogql.raw(
    'uuid, event, timestamp, elements_chain, properties.$window_id, properties.$current_url, properties.$event_type, distinct_id'
)

// hogql writes a Dayjs in the project timezone without an offset. In the hour that a daylight saving change repeats,
// a lower bound can then come out later than its upper bound, so the flag_evaluations reads write UTC bounds.
function utcBound(instant: Dayjs): HogQLRaw {
    return hogql.raw(`toDateTime(${escapeHogQLString(instant.utc().format('YYYY-MM-DD HH:mm:ss'))}, 'UTC')`)
}

/** The query's rows, or null after the failure is reported. */
async function queryRows(query: HogQLQueryString, feature: string): Promise<any[] | null> {
    try {
        const response = await api.queryHogQL(query, TAGS)
        if (response.error) {
            throw new Error(response.error)
        }
        return response.results
    } catch (error) {
        posthog.captureException(error, { feature })
        return null
    }
}

function queryFlagEvaluations(query: HogQLQueryString | null): Promise<any[] | null> {
    return query ? queryRows(query, 'session-recording-flag-evaluations') : Promise.resolve([])
}

