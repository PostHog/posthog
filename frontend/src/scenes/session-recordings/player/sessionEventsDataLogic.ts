export const sessionEventsDataLogic = kea<sessionEventsDataLogicType>([
    path((key) => ['scenes', 'session-recordings', 'sessionEventsDataLogic', key]),
    props({} as SessionRecordingMetaLogicProps),
    key(({ sessionRecordingId }) => sessionRecordingId || 'no-session-recording-id'),
    connect((props: SessionRecordingMetaLogicProps) => {
        const metaLogic = sessionRecordingMetaLogic(props)
        return {
            values: [
                metaLogic,
                ['sessionPlayerMetaData'],
                primaryEventPropertiesModel,
                ['primaryProperties'],
                teamLogic,
                ['currentTeam'],
            ],
            actions: [
                metaLogic,
                ['loadRecordingMetaSuccess', 'loadRecordingFromFile'],
                primaryEventPropertiesModel,
                ['ensureLoadedForEvents'],
            ],
        }
    }),
    actions({
        loadEvents: true,
        loadFullEventData: (event: RecordingEventType | RecordingEventType[]) => ({ event }),
    }),
    reducers(() => ({
        // File playback loads no events, so a raw export carries its viewports in its header.
        fileViewports: [
            [] as ExportedViewport[],
            {
                loadRecordingFromFile: (_, { recording }) => recording.viewports ?? [],
            },
        ],
    })),
    loaders(({ values, props }) => ({
        sessionEventsData: [
            null as null | RecordingEventType[],
            {
                loadEvents: async (_, breakpoint) => {
                    const meta = values.sessionPlayerMetaData
                    if (!meta) {
                        return null
                    }

                    const start = meta.start_time ? dayjs(meta.start_time) : null
                    const end = meta.end_time ? dayjs(meta.end_time) : null
                    const person = meta.person

                    if (!person || !start || !end) {
                        return null
                    }

                    const sessionEventsQuery = hogql`
SELECT ${SESSION_EVENT_COLUMNS}
FROM events
WHERE timestamp > ${start.subtract(TWENTY_FOUR_HOURS_IN_MS, 'ms')}
AND timestamp < ${end.add(TWENTY_FOUR_HOURS_IN_MS, 'ms')}
AND $session_id = ${props.sessionRecordingId}
ORDER BY timestamp ASC
LIMIT 1000000`

                    let personFilter: HogQLQueryString | null = null
                    if (person?.uuid) {
                        personFilter = hogql`\nAND person_id = ${person.uuid}`
                    }
                    if (!person?.uuid && values.sessionPlayerMetaData?.distinct_id) {
                        personFilter = hogql`\nAND distinct_id = ${values.sessionPlayerMetaData.distinct_id}`
                    }

                    const relatedEventsQuery = (hogql`
SELECT ${RELATED_EVENT_COLUMNS}
FROM events
WHERE timestamp > ${start.subtract(FIVE_MINUTES_IN_MS, 'ms')}
AND timestamp < ${end.add(FIVE_MINUTES_IN_MS, 'ms')}
AND (empty ($session_id) OR isNull($session_id))
AND properties.$lib != 'web'` +
                        (personFilter ?? '') +
                        hogql`\nORDER BY timestamp ASC\nLIMIT 1000000`) as HogQLQueryString

                    const readsFlagEvaluations = flagCallsOnlyInFlagEvaluations(values.currentTeam)
                    const flagCallsQuery = readsFlagEvaluations
                        ? hogql`
SELECT ${SESSION_EVENT_COLUMNS}
FROM ${hogql.raw(FLAG_EVALUATIONS_TABLE)}
WHERE timestamp > ${utcBound(start.subtract(TWENTY_FOUR_HOURS_IN_MS, 'ms'))}
AND timestamp < ${utcBound(end.add(TWENTY_FOUR_HOURS_IN_MS, 'ms'))}
AND session_id = ${props.sessionRecordingId}
ORDER BY timestamp ASC
LIMIT 1000000`
                        : null
                    // flag_evaluations' person_id joins the person overrides, so no index serves a filter on it.
                    // The stored flag_evaluation_person_id has a bloom filter index. It misses a call made before a merge
                    // into this person until the overrides squash rewrites the call.
                    let flagCallsPersonFilter: HogQLQueryString | null = null
                    if (person?.uuid) {
                        flagCallsPersonFilter = hogql`\nAND flag_evaluation_person_id = ${person.uuid}`
                    }
                    if (!person?.uuid && values.sessionPlayerMetaData?.distinct_id) {
                        flagCallsPersonFilter = hogql`\nAND distinct_id = ${values.sessionPlayerMetaData.distinct_id}`
                    }
                    // Without a person filter the read would cover every server-side flag call of the team.
                    const relatedFlagCallsQuery =
                        readsFlagEvaluations && flagCallsPersonFilter
                            ? ((hogql`
SELECT ${RELATED_EVENT_COLUMNS}
FROM ${hogql.raw(FLAG_EVALUATIONS_TABLE)}
WHERE timestamp > ${utcBound(start.subtract(FIVE_MINUTES_IN_MS, 'ms'))}
AND timestamp < ${utcBound(end.add(FIVE_MINUTES_IN_MS, 'ms'))}
AND empty(session_id)
AND properties.$lib != 'web'` +
                                  flagCallsPersonFilter +
                                  hogql`\nORDER BY timestamp ASC\nLIMIT 1000000`) as HogQLQueryString)
                            : null

                    const [sessionEvents, relatedEvents, flagCalls, relatedFlagCalls]: any[] = await Promise.all([
                        // make one query for all events that are part of the session
                        api.queryHogQL(sessionEventsQuery, TAGS),
                        // make a second for all events from that person,
                        // not marked as part of the session
                        // but in the same time range
                        // these are probably e.g. backend events for the session
                        // but with no session id
                        // since posthog-js must always add session id we can also
                        // take advantage of lib being materialized and further filter
                        api.queryHogQL(relatedEventsQuery, TAGS),
                        queryFlagEvaluations(flagCallsQuery),
                        queryFlagEvaluations(relatedFlagCallsQuery),
                    ])

                    breakpoint()

                    const rows = [...sessionEvents.results, ...relatedEvents.results]
                    const flagCallRows = [...(flagCalls ?? []), ...(relatedFlagCalls ?? [])]
                    // Flag calls from before the organization moved to flag_evaluations can be in both tables.
                    // Both copies carry the same uuid.
                    const allRows = flagCallRows.length
                        ? uniqueBy([...rows, ...flagCallRows], (row: any) => row[0])
                        : rows

                    return allRows.map((event: any): RecordingEventType => {
                        const currentUrl = event[5]
                        // We use the pathname to simplify the UI - we build it here instead of fetching it to keep data usage small
                        let pathname: string | undefined
                        try {
                            pathname = event[5] ? new URL(event[5]).pathname : undefined
                        } catch {
                            pathname = undefined
                        }

                        const viewportWidth = event.length > 7 ? event[7] : undefined
                        const viewportHeight = event.length > 8 ? event[8] : undefined

                        return {
                            id: event[0],
                            event: event[1],
                            timestamp: event[2],
                            elements: chainToElements(event[3]),
                            properties: {
                                $window_id: event[4],
                                $current_url: currentUrl,
                                $event_type: event[6],
                                $pathname: pathname,
                                $viewport_width: viewportWidth,
                                $viewport_height: viewportHeight,
                                $screen_name: event.length > 9 ? event[9] : undefined,
                            },
                            playerTime: +dayjs(event[2]) - +start,
                            fullyLoaded: false,
                            distinct_id: event[event.length - 1] || values.sessionPlayerMetaData?.distinct_id,
                        }
                    })
                },

                loadFullEventData: async ({ event }, breakpoint) => {
                    // box so we're always dealing with a list
                    const events = Array.isArray(event) ? event : [event]

                    // Cache before awaits — the logic may unmount during the API call
                    const cachedSessionEventsData = values.sessionEventsData

                    let existingEvents = cachedSessionEventsData?.filter((x) => events.some((e) => e.id === x.id))

                    const allEventsAreFullyLoaded =
                        existingEvents?.every((e) => e.fullyLoaded) && existingEvents.length === events.length
                    if (!existingEvents || allEventsAreFullyLoaded) {
                        return cachedSessionEventsData
                    }

                    existingEvents = existingEvents.filter((e) => !e.fullyLoaded)
                    if (!existingEvents.length) {
                        // nothing left to load (e.g. the events list was replaced while this action
                        // was queued) — bail out before reducing over an empty timestamps list
                        return cachedSessionEventsData
                    }
                    const timestamps = existingEvents.map((ee) => dayjs(ee.timestamp).utc().valueOf())
                    const eventNames = Array.from(new Set(existingEvents.map((ee) => ee.event)))
                    const eventIds = existingEvents.map((ee) => ee.id)
                    const flagCallEvents = flagCallsOnlyInFlagEvaluations(values.currentTeam)
                        ? existingEvents.filter((ee) => ee.event === FEATURE_FLAG_CALLED_EVENT)
                        : []
                    const flagCallIds = flagCallEvents.map((ee) => ee.id)
                    const flagCallDistinctIds = Array.from(
                        new Set(flagCallEvents.map((ee) => ee.distinct_id).filter(Boolean))
                    )
                    const earliestTimestamp = timestamps.reduce((a, b) => Math.min(a, b))
                    const latestTimestamp = timestamps.reduce((a, b) => Math.max(a, b))

                    try {
                        const query = hogql`
                            SELECT properties, uuid
                            FROM events
                            -- the timestamp range here is only to avoid querying too much of the events table
                            -- we don't really care about the absolute value,
                            -- but we do care about whether timezones have an odd impact
                            -- so, we extend the range by a day on each side so that timezones don't cause issues
                            WHERE timestamp > ${dayjs(earliestTimestamp).subtract(1, 'day')}
                            AND timestamp < ${dayjs(latestTimestamp).add(1, 'day')}
                            AND event in ${eventNames}
                            AND uuid in ${eventIds}`
                        // The rows carry exact timestamps, so a few minutes of padding finds them.
                        // An empty session_id matches the server-side flag calls that loadEvents lists. A row does not
                        // record which read listed it, and an OR across session_id and distinct_id stops both indexes.
                        const flagCallsQuery = flagCallIds.length
                            ? hogql`
                            SELECT properties, uuid
                            FROM ${hogql.raw(FLAG_EVALUATIONS_TABLE)}
                            WHERE timestamp > ${utcBound(dayjs(earliestTimestamp).subtract(FIVE_MINUTES_IN_MS, 'ms'))}
                            AND timestamp < ${utcBound(dayjs(latestTimestamp).add(FIVE_MINUTES_IN_MS, 'ms'))}
                            AND session_id in ${[props.sessionRecordingId, '']}
                            AND distinct_id in ${flagCallDistinctIds}
                            AND uuid in ${flagCallIds}`
                            : null

                        const [eventRows, flagCalls] = await Promise.all([
                            queryRows(query, 'session-recording-load-full-event-data'),
                            queryFlagEvaluations(flagCallsQuery),
                        ])
                        breakpoint()
                        // A flag call that the events table holds wins, because its row goes into the map last.
                        const propertiesById = new Map<string, string>(
                            [...(flagCalls ?? []), ...(eventRows ?? [])].map((row: any) => [row[1], row[0]])
                        )

                        for (const event of existingEvents) {
                            const properties = propertiesById.get(event.id)
                            if (properties) {
                                event.properties = JSON.parse(properties)
                                event.fullyLoaded = true
                            } else if (eventRows === null || (flagCalls === null && flagCallIds.includes(event.id))) {
                                // A row whose read failed keeps its summary properties, so its detail view stops loading.
                                event.fullyLoaded = true
                            }
                        }
                    } catch (e: any) {
                        if (isBreakpoint(e)) {
                            throw e
                        }
                        // NOTE: This is not ideal but should happen so rarely that it is tolerable.
                        existingEvents.forEach((e) => (e.fullyLoaded = true))
                        posthog.captureException(e, { feature: 'session-recording-load-full-event-data' })
                    }

                    // here we map the events list because we want the result to be a new instance to trigger downstream recalculation
                    return !cachedSessionEventsData
                        ? cachedSessionEventsData
                        : cachedSessionEventsData.map((x) => {
                              const event = existingEvents?.find((ee) => ee.id === x.id)
                              return event
                                  ? ({
                                        ...x,
                                        properties: event.properties,
                                        fullyLoaded: event.fullyLoaded,
                                    } as RecordingEventType)
                                  : x
                          })
                },
            },
        ],
    })),
    listeners(({ actions }) => ({
        loadRecordingMetaSuccess: () => {
            actions.loadEvents()
        },
        loadEventsSuccess: ({ sessionEventsData }) => {
            // Make sure the primary-property override map is populated for every event in the
            // recording, so the `eventsWithPrimaryProperty` selector can preload them.
            if (sessionEventsData?.length) {
                actions.ensureLoadedForEvents(Array.from(new Set(sessionEventsData.map((e) => e.event))))
            }
        },
    })),
    selectors(() => ({
        webVitalsEvents: [
            (s) => [s.sessionEventsData],
            (sessionEventsData: RecordingEventType[] | null): RecordingEventType[] =>
                (sessionEventsData || []).filter((e) => e.event === '$web_vitals'),
        ],
        AIEvents: [
            (s) => [s.sessionEventsData],
            (sessionEventsData: RecordingEventType[] | null): RecordingEventType[] =>
                // see if event start with $ai_
                (sessionEventsData || []).filter((e) => e.event.startsWith('$ai_')),
        ],
        exceptionEvents: [
            (s) => [s.sessionEventsData],
            (sessionEventsData: RecordingEventType[] | null): RecordingEventType[] =>
                (sessionEventsData || []).filter((e) => e.event === '$exception'),
        ],
        eventsWithPrimaryProperty: [
            (s) => [s.sessionEventsData, s.primaryProperties],
            (
                sessionEventsData: RecordingEventType[] | null,
                primaryProperties: Record<string, string>
            ): RecordingEventType[] => getEventsWithPrimaryProperty(sessionEventsData || [], primaryProperties),
        ],
        preloadableEvents: [
            (s) => [s.webVitalsEvents, s.AIEvents, s.exceptionEvents, s.eventsWithPrimaryProperty],
            (
                webVitalsEvents: RecordingEventType[],
                AIEvents: RecordingEventType[],
                exceptionEvents: RecordingEventType[],
                eventsWithPrimaryProperty: RecordingEventType[]
            ): RecordingEventType[] => {
                const seen = new Set<string>()
                const merged: RecordingEventType[] = []
                for (const e of [...webVitalsEvents, ...AIEvents, ...exceptionEvents, ...eventsWithPrimaryProperty]) {
                    if (!seen.has(e.id)) {
                        seen.add(e.id)
                        merged.push(e)
                    }
                }
                return merged
            },
            { resultEqualityCheck: equal },
        ],
        eventViewportsItems: [
            (s) => [s.sessionEventsData, s.fileViewports],
            (
                sessionEventsData: RecordingEventType[] | null,
                fileViewports: ExportedViewport[]
            ): TimeTree<{
                timestamp: Dayjs
                payload: ViewportResolution
            }> => {
                const viewportEvents = new TimeTree<{
                    timestamp: Dayjs
                    payload: ViewportResolution
                }>()
                viewportEvents.add(
                    (sessionEventsData || [])
                        .filter((e) => e.properties.$viewport_width && e.properties.$viewport_height)
                        .map((e) => ({
                            timestamp: dayjs(e.timestamp),
                            payload: {
                                width: e.properties.$viewport_width,
                                height: e.properties.$viewport_height,
                                href: e.properties.$current_url,
                            },
                        }))
                        .concat(
                            fileViewports.map(({ timestamp, ...payload }) => ({ timestamp: dayjs(timestamp), payload }))
                        )
                )
                return viewportEvents
            },
            { resultEqualityCheck: equal },
        ],
        viewportForTimestamp: [
            (s) => [s.eventViewportsItems],
            (
                eventViewportsItems: TimeTree<{
                    payload: ViewportResolution
                    timestamp: Dayjs
                }>
            ) => {
                return (timestamp: number) => {
                    const closestItem =
                        eventViewportsItems.next(dayjs(timestamp)) || eventViewportsItems.previous(dayjs(timestamp))
                    if (!closestItem) {
                        return undefined
                    }
                    return closestItem.payload as ViewportResolution
                }
            },
        ],
    })),
    subscriptions(({ actions }) => ({
        preloadableEvents: (pe: null | RecordingEventType[]) => {
            if (pe?.length) {
                actions.loadFullEventData(pe)
            }
        },
    })),
    beforeUnmount(({ cache }) => {
        cache.windowIdForTimestamp = undefined
        cache.viewportForTimestamp = undefined
        cache.processingCache = undefined
    }),
])
