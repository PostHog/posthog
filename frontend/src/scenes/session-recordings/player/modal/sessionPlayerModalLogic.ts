import { MakeLogicType, actions, kea, listeners, path, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { closeTraceDialogUnderModal } from 'lib/components/ViewTraceButton/traceDialogOpenLogic'

import { SessionRecordingId, SessionRecordingType } from '~/types'

interface HashParams {
    sessionRecordingId?: SessionRecordingId
}

interface QueryParams {
    timestamp?: number
}

export interface HeatmapBackgroundSelectionContext {
    type: 'heatmap-background-selection'
    targetUrl: string
    matchingRecordingCount: number
}

export type SessionPlayerModalContext = HeatmapBackgroundSelectionContext | null

export interface SessionPlayerModalRecordingListEntry {
    sessionRecording: Pick<SessionRecordingType, 'id' | 'matching_events'>
    personDisplayName: string | null
}

/** The opener owns the order, and the list does not change while the player is open. */
export interface SessionPlayerModalRecordingList {
    entries: SessionPlayerModalRecordingListEntry[]
    position: number
    hasMoreToLoad: boolean
}

function validRecordingList(
    sessionRecording: Pick<SessionRecordingType, 'id'>,
    recordingList: SessionPlayerModalRecordingList | null
): SessionPlayerModalRecordingList | null {
    // A list that does not hold the opened recording at its position would show a wrong position in the header
    // and play the wrong next recording, so the player opens without navigation instead.
    return recordingList?.entries[recordingList.position]?.sessionRecording.id === sessionRecording.id
        ? recordingList
        : null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sessionPlayerModalLogicValues {
    activeSessionRecording: Pick<SessionRecordingType, 'id' | 'matching_events'> | null
    hasNextRecordingInList: boolean
    initialTimestamp: number | null
    modalContext: SessionPlayerModalContext
    recordingList: SessionPlayerModalRecordingList | null
    showRecordingListPosition: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sessionPlayerModalLogicActions {
    closeSessionPlayer: () => {
        value: true
    }
    completeHeatmapBackgroundSelection: (storageKey: string) => {
        storageKey: string
    }
    openSessionPlayer: (
        sessionRecording: Pick<SessionRecordingType, 'id' | 'matching_events'>,
        initialTimestamp?: number | null,
        modalContext?: SessionPlayerModalContext,
        recordingList?: SessionPlayerModalRecordingList | null
    ) => {
        initialTimestamp: number | null
        modalContext: SessionPlayerModalContext
        recordingList: SessionPlayerModalRecordingList | null
        sessionRecording: Pick<SessionRecordingType, 'id' | 'matching_events'>
    }
    playNextRecordingInList: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sessionPlayerModalLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        hasNextRecordingInList: (recordingList: SessionPlayerModalRecordingList | null) => boolean
        showRecordingListPosition: (recordingList: SessionPlayerModalRecordingList | null) => boolean
    }
}

export type sessionPlayerModalLogicType = MakeLogicType<
    sessionPlayerModalLogicValues,
    sessionPlayerModalLogicActions,
    Record<string, any>,
    sessionPlayerModalLogicMeta
>

export const sessionPlayerModalLogic = kea<sessionPlayerModalLogicType>([
    path(['scenes', 'session-recordings', 'sessionPlayerModalLogic']),
    actions({
        openSessionPlayer: (
            sessionRecording: Pick<SessionRecordingType, 'id' | 'matching_events'>,
            initialTimestamp: number | null = null,
            modalContext: SessionPlayerModalContext = null,
            recordingList: SessionPlayerModalRecordingList | null = null
        ) => ({
            sessionRecording,
            initialTimestamp,
            modalContext,
            recordingList: validRecordingList(sessionRecording, recordingList),
        }),
        closeSessionPlayer: true,
        playNextRecordingInList: true,
        completeHeatmapBackgroundSelection: (storageKey: string) => ({ storageKey }),
    }),
    reducers({
        activeSessionRecording: [
            null as Pick<SessionRecordingType, 'id' | 'matching_events'> | null,
            {
                openSessionPlayer: (_, { sessionRecording }) => sessionRecording,
                closeSessionPlayer: () => null,
            },
        ],
        initialTimestamp: [
            null as number | null,
            {
                openSessionPlayer: (_, { initialTimestamp }) => initialTimestamp,
                closeSessionPlayer: () => null,
            },
        ],
        modalContext: [
            null as SessionPlayerModalContext,
            {
                openSessionPlayer: (_, { modalContext }) => modalContext,
                closeSessionPlayer: () => null,
            },
        ],
        recordingList: [
            null as SessionPlayerModalRecordingList | null,
            {
                openSessionPlayer: (_, { recordingList }) => recordingList,
                closeSessionPlayer: () => null,
            },
        ],
    }),
    selectors({
        hasNextRecordingInList: [
            (s) => [s.recordingList],
            (recordingList: SessionPlayerModalRecordingList | null): boolean =>
                !!recordingList && recordingList.position < recordingList.entries.length - 1,
        ],
        showRecordingListPosition: [
            (s) => [s.recordingList],
            // A single recording with nothing left to load has nowhere to go, so the player looks as it does
            // when it is opened without a list.
            (recordingList: SessionPlayerModalRecordingList | null): boolean =>
                !!recordingList && (recordingList.entries.length > 1 || recordingList.hasMoreToLoad),
        ],
    }),
    listeners(({ actions, values }) => ({
        openSessionPlayer: () => {
            closeTraceDialogUnderModal()
        },
        playNextRecordingInList: () => {
            const { recordingList } = values
            if (!recordingList || !values.hasNextRecordingInList) {
                return
            }
            const position = recordingList.position + 1
            actions.openSessionPlayer(recordingList.entries[position].sessionRecording, null, null, {
                ...recordingList,
                position,
            })
        },
    })),
    actionToUrl(({ values }) => {
        const buildURL = (): [
            string,
            Record<string, any>,
            Record<string, any>,
            {
                replace: boolean
            },
        ] => {
            const hashParams: HashParams = {
                ...router.values.hashParams,
            }
            const searchParams: QueryParams = {
                ...router.values.searchParams,
            }

            if (!values.activeSessionRecording?.id) {
                delete hashParams.sessionRecordingId
            } else {
                hashParams.sessionRecordingId = values.activeSessionRecording.id
            }

            if (!values.initialTimestamp) {
                delete searchParams.timestamp
            } else {
                searchParams.timestamp = values.initialTimestamp
            }

            return [router.values.location.pathname, searchParams, hashParams, { replace: true }]
        }

        return {
            openSessionPlayer: () => buildURL(),
            closeSessionPlayer: () => buildURL(),
        }
    }),
    urlToAction(({ actions, values }) => {
        const urlToAction = (_: any, searchParams: QueryParams, hashParams: HashParams): void => {
            // Check if the logic is still mounted. Because this is called on every URL change, the logic might have been unmounted already.
            if (sessionPlayerModalLogic.isMounted()) {
                const nulledSessionRecordingId = hashParams.sessionRecordingId ?? null
                const initialTimestamp = searchParams.timestamp ?? null
                if (nulledSessionRecordingId && nulledSessionRecordingId !== values.activeSessionRecording?.id) {
                    actions.openSessionPlayer({ id: nulledSessionRecordingId }, initialTimestamp)
                }
            }
        }
        return {
            '*': urlToAction,
        }
    }),
])
