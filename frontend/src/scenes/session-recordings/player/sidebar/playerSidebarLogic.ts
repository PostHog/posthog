import { MakeLogicType, actions, kea, path, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { SessionRecordingSidebarTab } from '~/types'

// `tab` is the search param scenes conventionally own, so the sidebar keeps its own tab under a
// player-specific key. Writing `tab` from here overwrites the value of whichever scene embeds the
// player, and a scene that resolves an unrecognized `tab` back to its default then throws the
// viewer out of the recording they were watching.
const SIDEBAR_TAB_PARAM = 'sidebarTab'

// kea-router coerces numeric-looking params to numbers, so check the type before membership
const isSidebarTab = (tab: unknown): tab is SessionRecordingSidebarTab =>
    typeof tab === 'string' && (Object.values(SessionRecordingSidebarTab) as string[]).includes(tab)

// Links shared before the param was namespaced carry the sidebar tab as `tab`, so both keys are
// still read. The namespaced key wins wherever both are present, and search wins over hash.
const getSidebarTabFromUrl = (
    searchParams: Record<string, any>,
    hashParams: Record<string, any>
): SessionRecordingSidebarTab | null =>
    [searchParams[SIDEBAR_TAB_PARAM], hashParams[SIDEBAR_TAB_PARAM], searchParams.tab, hashParams.tab].find(
        isSidebarTab
    ) ?? null

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface playerSidebarLogicValues {
    activeTab: SessionRecordingSidebarTab
    defaultTab: SessionRecordingSidebarTab
    selectedTab: SessionRecordingSidebarTab | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface playerSidebarLogicActions {
    setDefaultTab: (tab: SessionRecordingSidebarTab) => {
        tab: SessionRecordingSidebarTab
    }
    setTab: (tab: SessionRecordingSidebarTab) => {
        tab: SessionRecordingSidebarTab
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface playerSidebarLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        activeTab: (
            selectedTab: SessionRecordingSidebarTab | null,
            defaultTab: SessionRecordingSidebarTab
        ) => SessionRecordingSidebarTab
    }
}

export type playerSidebarLogicType = MakeLogicType<
    playerSidebarLogicValues,
    playerSidebarLogicActions,
    Record<string, any>,
    playerSidebarLogicMeta
>

export const playerSidebarLogic = kea<playerSidebarLogicType>([
    path(() => ['scenes', 'session-recordings', 'player', 'playerSidebarLogic']),

    actions(() => ({
        setTab: (tab: SessionRecordingSidebarTab) => ({ tab }),
        setDefaultTab: (tab: SessionRecordingSidebarTab) => ({ tab }),
    })),

    reducers(() => ({
        // The tab the viewer picked, or null while they haven't picked one.
        selectedTab: [null as SessionRecordingSidebarTab | null, { setTab: (_, { tab }) => tab }],
        // Where the sidebar lands until the viewer picks a tab. Hosts embedding the player set this
        // to whichever tab their surface is about — the experiment recordings tab wants Overview,
        // since that's where the experiment context lives.
        defaultTab: [
            SessionRecordingSidebarTab.INSPECTOR as SessionRecordingSidebarTab,
            { setDefaultTab: (_, { tab }) => tab },
        ],
    })),

    selectors({
        activeTab: [
            (s) => [s.selectedTab, s.defaultTab],
            (
                selectedTab: SessionRecordingSidebarTab | null,
                defaultTab: SessionRecordingSidebarTab
            ): SessionRecordingSidebarTab => selectedTab ?? defaultTab,
        ],
    }),

    actionToUrl(() => ({
        // Only the viewer's own pick belongs in the URL. A host's default describes where the player
        // is embedded, not what the viewer chose, so `setDefaultTab` deliberately has no entry here.
        setTab: ({ tab }) => {
            const { currentLocation } = router.values
            const searchParams: Record<string, any> = {
                ...currentLocation.searchParams,
                [SIDEBAR_TAB_PARAM]: tab,
            }
            // A `tab` holding a sidebar value is this logic's own leftover from a pre-namespace
            // link. Dropping it stops the URL from carrying two sidebar tabs that disagree, which
            // would otherwise be shared as an ambiguous link. A `tab` holding anything else is the
            // host scene's, so it stays untouched.
            if (isSidebarTab(searchParams.tab)) {
                delete searchParams.tab
            }
            return [currentLocation.pathname, searchParams, currentLocation.hashParams]
        },
    })),

    urlToAction(({ actions, values }) => ({
        '*': (_, searchParams, hashParams) => {
            const isShowingRecording =
                Object.keys(searchParams).includes('sessionRecordingId') ||
                Object.keys(hashParams).includes('sessionRecordingId')
            const urlTab = getSidebarTabFromUrl(searchParams, hashParams)

            // Compared against the viewer's pick rather than the active tab: a tab in the URL is an
            // explicit choice, and checking the active tab would skip recording it whenever a host
            // default happened to match — the choice would then evaporate once that host went away.
            if (isShowingRecording && urlTab && urlTab !== values.selectedTab) {
                actions.setTab(urlTab)
            }
        },
    })),
])
