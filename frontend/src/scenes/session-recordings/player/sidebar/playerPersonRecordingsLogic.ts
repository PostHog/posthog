export type playerPersonRecordingsLogicType = MakeLogicType<
    playerPersonRecordingsLogicValues,
    playerPersonRecordingsLogicActions,
    SessionRecordingPlayerLogicProps,
    playerPersonRecordingsLogicMeta
>

export const playerPersonRecordingsLogic = kea<playerPersonRecordingsLogicType>([
    path((key) => ['scenes', 'session-recordings', 'player', 'sidebar', 'playerPersonRecordingsLogic', key]),
    props({} as SessionRecordingPlayerLogicProps),
    // Keyed per recording: sessionPerson isn't available synchronously when the key is
    // computed, so we can't key on the person. Each jump remounts and refetches one page.
    key((props: SessionRecordingPlayerLogicProps) => `${props.playerKey}-${props.sessionRecordingId}`),
    connect((props: SessionRecordingPlayerLogicProps) => ({
        values: [
            playerMetaLogic(props),
            ['sessionPerson', 'sessionPlayerMetaData'],
            sessionRecordingPlayerLogic(props),
            ['sessionRecordingId'],
        ],
        actions: [playerMetaLogic(props), ['loadRecordingMetaSuccess']],
    })),
    loaders(({ values }) => ({
        recordingsResponse: [
            null as RecordingsQueryResponse | null,
            {
                loadRecordings: async (_, breakpoint) => {
                    const person = values.sessionPerson
                    if (!person?.uuid) {
                        return null
                    }
                    const dateFrom = retentionDateFrom(values.sessionPlayerMetaData?.retention_period_days)
                    const response = await api.recordings.list(
                        personRecordingsQuery(person.uuid, person.distinct_ids, dateFrom)
                    )
                    breakpoint()
                    return response
                },
                loadMoreRecordings: async (_, breakpoint) => {
                    const person = values.sessionPerson
                    const cursor = values.recordingsResponse?.next_cursor
                    if (!person?.uuid || !cursor) {
                        return values.recordingsResponse
                    }
                    const dateFrom = retentionDateFrom(values.sessionPlayerMetaData?.retention_period_days)
                    const response = await api.recordings.list(
                        personRecordingsQuery(person.uuid, person.distinct_ids, dateFrom, cursor)
                    )
                    breakpoint()
                    return mergeRecordingPage(values.recordingsResponse, response)
                },
            },
        ],
    })),
    reducers(() => ({
        // Distinguishes "loaded, genuinely few recordings" from "still loading or errored",
        // so the empty state only renders once a successful response has come back.
        hasLoaded: [
            false,
            {
                loadRecordingsSuccess: () => true,
            },
        ],
        // Initial-load failure: replaces the whole tab with a retry.
        loadError: [
            false,
            {
                loadRecordings: () => false,
                loadRecordingsSuccess: () => false,
                loadRecordingsFailure: () => true,
            },
        ],
        // "Load older" failure: surfaced next to the button so the already-loaded list stays put.
        loadMoreError: [
            false,
            {
                loadMoreRecordings: () => false,
                loadMoreRecordingsSuccess: () => false,
                loadMoreRecordingsFailure: () => true,
            },
        ],
    })),
    selectors(() => ({
        recordings: [
            (s) => [s.recordingsResponse],
            (recordingsResponse: RecordingsQueryResponse | null): SessionRecordingType[] =>
                recordingsResponse?.results ?? [],
        ],
        hasMore: [
            (s) => [s.recordingsResponse],
            (recordingsResponse: RecordingsQueryResponse | null): boolean => !!recordingsResponse?.has_next,
        ],
    })),
    listeners(({ actions, values }) => {
        const maybeLoad = (): void => {
            if (values.sessionPerson?.uuid && !values.recordingsResponse && !values.recordingsResponseLoading) {
                actions.loadRecordings({})
            }
        }
        return {
            // The person only exists after metadata loads. Metadata may resolve before or after
            // this tab is opened, so cover both: fetch on meta success and on mount.
            loadRecordingMetaSuccess: maybeLoad,
        }
    }),
    afterMount(({ actions, values }) => {
        if (values.sessionPerson?.uuid && !values.recordingsResponse && !values.recordingsResponseLoading) {
            actions.loadRecordings({})
        }
    }),
])
