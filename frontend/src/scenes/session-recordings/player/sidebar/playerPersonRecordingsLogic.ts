import { MakeLogicType, afterMount, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'

import { NodeKind, RecordingsQuery, RecordingsQueryResponse } from '~/queries/schema/schema-general'
import { PersonType, SessionRecordingType } from '~/types'

import { playerMetaLogic } from '../player-meta/playerMetaLogic'
import { SessionRecordingPlayerLogicProps, sessionRecordingPlayerLogic } from '../sessionRecordingPlayerLogic'

// One page is plenty for the common "which other session was this" case; a
// "Load older" control walks the cursor for people with long histories.
const PAGE_SIZE = 50

// Fallback window when the recording's retention period is unknown.
const DEFAULT_RETENTION_DAYS = 30

// The recordings query defaults to the last 3 days server-side, which would hide older
// sessions and even the current recording if it's older than that. Scope the window to the
// team's recording retention period instead: nothing older can still exist, and the current
// recording is by definition within it. A one-day buffer avoids edge-of-window rounding.
export function retentionDateFrom(retentionPeriodDays: number | null | undefined): string {
    return `-${(retentionPeriodDays ?? DEFAULT_RETENTION_DAYS) + 1}d`
}

function personRecordingsQuery(
    personUuid: string,
    distinctIds: string[] | undefined,
    dateFrom: string,
    after?: string
): RecordingsQuery {
    return {
        kind: NodeKind.RecordingsQuery,
        person_uuid: personUuid,
        // person_uuid resolves the person server-side; skip distinct_ids for heavily merged
        // persons to avoid an unwieldy query string. Matches sessionRecordingsPlaylistLogic.
        distinct_ids: (distinctIds?.length ?? 0) < 100 ? distinctIds : undefined,
        date_from: dateFrom,
        order: 'start_time',
        order_direction: 'DESC',
        limit: PAGE_SIZE,
        after,
    }
}

// Append the next page onto the accumulated results so "Load older" grows the list
// rather than replacing it. Keeps the newer response's has_next / next_cursor.
export function mergeRecordingPage(
    previous: RecordingsQueryResponse | null,
    next: RecordingsQueryResponse
): RecordingsQueryResponse {
    return { ...next, results: [...(previous?.results ?? []), ...next.results] }
}

