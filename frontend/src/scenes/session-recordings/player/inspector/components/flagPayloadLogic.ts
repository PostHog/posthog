import { MakeLogicType, connect, kea, key, path, props } from 'kea'
import type { LogicWrapper } from 'kea'
import { lazyLoaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { featureFlagsVersionsRetrieve } from 'products/feature_flags/frontend/generated/api'

export interface FlagPayloadLogicProps {
    /** From the event's `$feature_flag_id` property. */
    flagId: number
    /** From the event's `$feature_flag_version` property. */
    version: number
    /**
     * Key into the flag's `payloads` map, derived from `$feature_flag_response`. This is the
     * served variant, or `'true'` for a boolean or remote config flag.
     */
    payloadKey: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface flagPayloadLogicValues {
    currentProjectId: number | string // teamLogic
    flagPayload: string | null
    flagPayloadLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface flagPayloadLogicActions {
    loadFlagPayload: () => any
    loadFlagPayloadFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadFlagPayloadSuccess: (
        flagPayload: string | null,
        payload?: any
    ) => {
        flagPayload: string | null
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface flagPayloadLogicMeta {
    key: string
}

export type flagPayloadLogicType = MakeLogicType<
    flagPayloadLogicValues,
    flagPayloadLogicActions,
    FlagPayloadLogicProps,
    flagPayloadLogicMeta
>

export const flagPayloadLogic: LogicWrapper<flagPayloadLogicType> = kea<flagPayloadLogicType>([
    props({} as FlagPayloadLogicProps),
    key((props: FlagPayloadLogicProps) => `${props.flagId}-${props.version}-${props.payloadKey}`),
    path((key) => ['scenes', 'session-recordings', 'player', 'inspector', 'flagPayloadLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),
    lazyLoaders(({ props, values }) => ({
        flagPayload: [
            null as string | null,
            {
                loadFlagPayload: async (): Promise<string | null> => {
                    // Reconstruction is best-effort: encrypted payloads are refused, deleted flags
                    // 404, and gaps in the activity log 422. None of those are worth surfacing on a
                    // replay event, so fall back to showing nothing.
                    try {
                        const version = await featureFlagsVersionsRetrieve(
                            String(values.currentProjectId),
                            props.flagId,
                            props.version
                        )
                        const payloads = version.filters?.payloads as Record<string, string> | undefined
                        return payloads?.[props.payloadKey] ?? null
                    } catch {
                        return null
                    }
                },
            },
        ],
    })),
])
