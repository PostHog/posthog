export type debugReplayChatLogicType = MakeLogicType<debugReplayChatLogicValues, debugReplayChatLogicActions>

/**
 * Remembers which PostHog AI chat debugged each recording, so that the player can reopen that chat.
 *
 * A task has no reference to a recording on the server. The link exists only in this browser's local storage.
 */
export const debugReplayChatLogic = kea<debugReplayChatLogicType>([
    path(['scenes', 'session-recordings', 'player', 'player-meta', 'debugReplayChatLogic']),
    connect(() => ({
        values: [maxGlobalLogic, ['effectivePhaiView'], projectLogic, ['currentProjectId']],
        actions: [
            runnerPanelLogic({ panelId: MAX_SIDE_PANEL_ID }),
            ['setActiveCreation', 'clearActiveCreation'],
            sidePanelStateLogic,
            ['openSidePanel'],
            sessionRecordingEventUsageLogic,
            ['reportRecordingDebugChatReopened'],
        ],
    })),
    actions({
        debugChatRequested: (sessionRecordingId: string) => ({ sessionRecordingId }),
        rememberDebugChat: (sessionRecordingId: string, taskId: string) => ({ sessionRecordingId, taskId }),
        forgetDebugChat: (sessionRecordingId: string) => ({ sessionRecordingId }),
        openDebugChat: (sessionRecordingId: string) => ({ sessionRecordingId }),
        openDebugChatFinished: true,
        loadDebugChatSummary: (sessionRecordingId: string) => ({ sessionRecordingId }),
        setDebugChatSummary: (sessionRecordingId: string, summary: DebugChatSummary) => ({
            sessionRecordingId,
            summary,
        }),
    }),
    reducers({
        taskIdBySessionRecordingId: [
            {} as Record<string, string>,
            { persist: true },
            {
                rememberDebugChat: (state, { sessionRecordingId, taskId }) => {
                    // Reinserting moves the recording to the end, so the entries stay ordered oldest first.
                    const { [sessionRecordingId]: _, ...rest } = state
                    const entries = [...Object.entries(rest), [sessionRecordingId, taskId]]
                    return Object.fromEntries(entries.slice(-MAX_REMEMBERED_DEBUG_CHATS))
                },
                forgetDebugChat: (state, { sessionRecordingId }) => {
                    const { [sessionRecordingId]: _, ...rest } = state
                    return rest
                },
            },
        ],
        pendingDebugChat: [
            null as PendingDebugChat | null,
            {
                debugChatRequested: (_, { sessionRecordingId }) => ({ sessionRecordingId, streamKey: null }),
                setActiveCreation: (state, { creation }) => {
                    if (!state) {
                        return state
                    }
                    if (state.streamKey === null) {
                        // The run for the prompt opens without a task. A creation that already has a task is
                        // a chat the user opened from history, so the prompt was not sent.
                        return creation.taskId ? null : { ...state, streamKey: creation.streamKey }
                    }
                    return creation.streamKey === state.streamKey ? state : null
                },
                clearActiveCreation: (state) => (state?.streamKey ? null : state),
                rememberDebugChat: () => null,
            },
        ],
        openingSessionRecordingId: [
            null as string | null,
            {
                openDebugChat: (_, { sessionRecordingId }) => sessionRecordingId,
                openDebugChatFinished: () => null,
            },
        ],
        debugChatSummaryBySessionRecordingId: [
            {} as Record<string, DebugChatSummary>,
            {
                setDebugChatSummary: (state, { sessionRecordingId, summary }) => ({
                    ...state,
                    [sessionRecordingId]: summary,
                }),
                forgetDebugChat: (state, { sessionRecordingId }) => {
                    const { [sessionRecordingId]: _, ...rest } = state
                    return rest
                },
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setActiveCreation: ({ creation }) => {
            const pending = values.pendingDebugChat
            // The panel sets the task on the optimistic run after the server creates it.
            if (pending?.streamKey === creation.streamKey && creation.taskId) {
                actions.rememberDebugChat(pending.sessionRecordingId, creation.taskId)
            }
        },
        loadDebugChatSummary: async ({ sessionRecordingId }) => {
            const taskId = values.taskIdBySessionRecordingId[sessionRecordingId]
            if (!taskId || values.currentProjectId === null) {
                return
            }
            try {
                const task = await tasksRetrieve(String(values.currentProjectId), taskId)
                actions.setDebugChatSummary(sessionRecordingId, summaryFromTask(task))
            } catch (error) {
                // The button falls back to its plain tooltip on any other error, so only a deleted task needs handling.
                if ((error as { status?: number } | null)?.status === 404) {
                    actions.forgetDebugChat(sessionRecordingId)
                }
            }
        },
        openDebugChat: async ({ sessionRecordingId }) => {
            const taskId = values.taskIdBySessionRecordingId[sessionRecordingId]
            if (!taskId || values.currentProjectId === null) {
                actions.openDebugChatFinished()
                return
            }
            try {
                const task = await tasksRetrieve(String(values.currentProjectId), taskId)
                actions.setDebugChatSummary(sessionRecordingId, summaryFromTask(task))
                actions.reportRecordingDebugChatReopened()
                if (values.effectivePhaiView === 'new' && task.latest_run) {
                    actions.openSidePanel(SidePanelTab.Max)
                    actions.setActiveCreation({
                        streamKey: task.latest_run.id,
                        taskId: task.id,
                        runId: task.latest_run.id,
                    })
                } else {
                    // The legacy chat panel cannot show a task, and a task without a run has no thread to show.
                    router.actions.push(urls.taskDetail(task.id))
                }
            } catch (error) {
                if ((error as { status?: number } | null)?.status === 404) {
                    actions.forgetDebugChat(sessionRecordingId)
                    lemonToast.error('That chat no longer exists. Debug this replay again to start a new one.')
                } else {
                    lemonToast.error("Couldn't open the chat. Try again in a moment.")
                }
            } finally {
                actions.openDebugChatFinished()
            }
        },
    })),
])
