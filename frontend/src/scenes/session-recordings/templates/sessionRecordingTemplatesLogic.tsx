export const sessionReplayTemplatesLogic = kea<sessionReplayTemplatesLogicType>([
    path(() => ['scenes', 'session-recordings', 'templates', 'sessionReplayTemplatesLogic']),
    props({} as ReplayTemplateLogicPropsType),
    key((props) => `${props.category}-${props.template.key}`),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
    })),
    actions({
        setVariables: (variables?: ReplayTemplateVariableType[]) => ({ variables }),
        setVariable: (variable: ReplayTemplateVariableType) => ({ variable }),
        resetVariable: (variable: ReplayTemplateVariableType) => ({ variable }),
        reportTemplateUsed: (source: ReplayTemplateUsedSource) => ({ source }),
        matchCountFailed: true,
        showVariables: true,
        hideVariables: true,
    }),
    reducers(({ props, values }) => ({
        variables: [
            props.template.variables ?? [],
            {
                persist: true,
                storageKey: clsx(
                    'session-recordings.templates.variables',
                    values.currentTeam?.id,
                    props.category,
                    props.template.key
                ),
            },
            {
                setVariables: (_, { variables }) => variables ?? [],
                setVariable: (state, { variable }) =>
                    state.map((v) => (v.key === variable.key ? { ...variable, touched: true } : v)),
                resetVariable: (state, { variable }) =>
                    state.map((v) => (v.key === variable.key ? { ...variable, touched: false } : v)),
            },
        ],
        variablesVisible: [
            false,
            {
                showVariables: () => true,
                hideVariables: () => false,
            },
        ],
        matchCountError: [
            false,
            {
                loadMatchCount: () => false,
                matchCountFailed: () => true,
            },
        ],
    })),
    loaders(({ actions, values }) => ({
        matchCount: [
            null as TemplateMatchCount | null,
            {
                loadMatchCount: async (_, breakpoint) => {
                    if (!values.hasTemplateFilters) {
                        return null
                    }
                    await breakpoint(300)
                    const query = {
                        ...convertUniversalFiltersToRecordingsQuery({
                            date_from: TEMPLATE_DATE_FROM,
                            date_to: null,
                            duration: [],
                            filter_test_accounts: false,
                            filter_group: values.filterGroup.filter_group ?? {
                                type: FilterLogicalOperator.And,
                                values: [],
                            },
                        }),
                        limit: MATCH_COUNT_LIMIT,
                    }
                    let response
                    try {
                        response = await api.recordings.list(query)
                    } catch {
                        actions.matchCountFailed()
                        return null
                    }
                    breakpoint()
                    return { count: response.results.length, hasMore: response.has_next }
                },
            },
        ],
    })),
    selectors({
        filterGroup: [
            (s) => [s.variables],
            (variables: ReplayTemplateVariableType[]) => {
                const filters = variables
                    .map((variable) => {
                        if (variable.type === 'pageview' && variable.value) {
                            return getPageviewFilterValue(variable.value)
                        }
                        if (
                            ['snapshot_source', 'event', 'person-property'].includes(variable.type) &&
                            variable.filterGroup
                        ) {
                            return variable.filterGroup
                        }
                        return undefined
                    })
                    .filter((filter): filter is UniversalFiltersGroupValue => filter !== undefined)

                const filterGroup: Partial<RecordingUniversalFilters> = {
                    filter_group: {
                        type: FilterLogicalOperator.And,
                        values: [
                            {
                                type: FilterLogicalOperator.And,
                                values: filters,
                            },
                        ],
                    },
                    // TODO this should set order on the filter group after https://github.com/PostHog/posthog/pull/25701
                }
                return filterGroup
            },
        ],
        previewFilters: [
            (s) => [s.filterGroup],
            (filterGroup: Partial<RecordingUniversalFilters>): UniversalFilterValue[] => {
                const innerGroup = filterGroup.filter_group?.values[0]
                return innerGroup && isUniversalGroupFilterLike(innerGroup)
                    ? innerGroup.values.filter(
                          (value): value is UniversalFilterValue => !isUniversalGroupFilterLike(value)
                      )
                    : []
            },
        ],
        hasTemplateFilters: [
            (s) => [s.previewFilters, s.variables],
            (previewFilters: UniversalFilterValue[], variables: ReplayTemplateVariableType[]) =>
                previewFilters.length > 0 || variables.length === 0,
        ],
        canApplyFilters: [
            (s) => [s.variables, s.areAnyVariablesTouched],
            (variables: ReplayTemplateVariableType[], areAnyVariablesTouched: boolean) =>
                areAnyVariablesTouched || variables.length === 0,
        ],
        areAnyVariablesTouched: [
            (s) => [s.variables],
            (variables: ReplayTemplateVariableType[]) =>
                variables.some((v) => v.touched) || variables.some((v) => v.noTouch),
        ],
        editableVariables: [
            (s) => [s.variables],
            (variables: ReplayTemplateVariableType[]) => variables.filter((v) => !v.noTouch),
        ],
    }),
    listeners(({ actions, props, values }) => ({
        showVariables: () => {
            actions.loadMatchCount()
        },
        setVariable: () => {
            if (values.variablesVisible) {
                actions.loadMatchCount()
            }
        },
        resetVariable: () => {
            if (values.variablesVisible) {
                actions.loadMatchCount()
            }
        },
        reportTemplateUsed: ({ source }) => {
            posthog.capture('session replay template used', {
                template: props.template.key,
                category: props.category,
                source,
            })
        },
    })),
    events(({ actions, props, values }) => ({
        afterMount: () => {
            if (values.variables.length === 0) {
                actions.setVariables(props.template.variables)
            }
        },
    })),
])
