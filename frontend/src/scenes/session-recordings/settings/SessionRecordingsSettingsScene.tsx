import { MakeLogicType, BindLogic, kea, path, selectors, useValues } from 'kea'
import { router } from 'kea-router'

import { sceneConfigurations } from 'scenes/scenes'
import { Scene, SceneExport } from 'scenes/sceneTypes'
import { Settings } from 'scenes/settings/Settings'
import { urls } from 'scenes/urls'

import { SceneContent } from '~/layout/scenes/components/SceneContent'
import { SceneTitleSection } from '~/layout/scenes/components/SceneTitleSection'
import { ProductKey } from '~/queries/schema/schema-general'
import { Breadcrumb, ReplayTabs } from '~/types'

import { playerSettingsLogic } from '../player/playerSettingsLogic'
import { isNewReplayLayout } from '../playlist/replayLayout'
import { SessionRecordingsPageTabs } from '../SessionRecordings'
import { sessionReplaySceneLogic } from '../sessionReplaySceneLogic'

export const SETTINGS_LOGIC_KEY = 'replaySettings'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sessionRecordingsSettingsSceneLogicValues {
    breadcrumbs: Breadcrumb[]
}

export type sessionRecordingsSettingsSceneLogicType = MakeLogicType<sessionRecordingsSettingsSceneLogicValues, {}>

export const sessionRecordingsSettingsSceneLogic = kea<sessionRecordingsSettingsSceneLogicType>([
    path(['scenes', 'session-recordings', 'settings', 'sessionRecordingsSettingsSceneLogic']),
    selectors({
        breadcrumbs: [
            () => [],
            (): Breadcrumb[] => [
                {
                    key: Scene.Replay,
                    path: urls.replay(),
                    name: 'Replay',
                    iconType: 'session_replay',
                },
                {
                    key: Scene.ReplaySettings,
                    path: urls.replaySettings(),
                    name: 'Settings',
                    iconType: 'session_replay',
                },
            ],
        ],
    }),
])

export const scene: SceneExport = {
    component: SessionRecordingsSettingsScene,
    logic: sessionRecordingsSettingsSceneLogic,
    productKey: ProductKey.SESSION_REPLAY,
}

export function SessionRecordingsSettingsScene(): JSX.Element {
    const { replayLayout } = useValues(playerSettingsLogic)
    const settingsUnderRecordings = isNewReplayLayout(replayLayout)
    const replayName = sceneConfigurations[Scene.Replay].name
    return (
        <BindLogic logic={sessionReplaySceneLogic} props={{}}>
            <SceneContent className="-mb-14">
                <SceneTitleSection
                    name={settingsUnderRecordings ? 'Settings' : replayName}
                    resourceType={{
                        type: sceneConfigurations[Scene.Replay].iconType || 'default_icon_type',
                    }}
                    forceBackTo={
                        settingsUnderRecordings
                            ? { key: Scene.Replay, name: replayName, path: urls.replay(ReplayTabs.Home) }
                            : undefined
                    }
                />
                <SessionRecordingsPageTabs />
                <Settings
                    logicKey={SETTINGS_LOGIC_KEY}
                    sectionId="environment-replay"
                    settingId={router.values.searchParams.sectionId || 'replay'}
                    handleLocally
                />
            </SceneContent>
        </BindLogic>
    )
}
