import { MakeLogicType, events, kea, path } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'

import { QueryLogTags } from '~/queries/schema/schema-general'
import { hogql } from '~/queries/utils'

const POLL_INTERVAL_MS = 60000

const QUERY_TAGS: QueryLogTags = { scene: 'Replay', productKey: 'session_replay' }

// The min_first_timestamp bound lets ClickHouse prune on the sort key; a session cannot run longer than a day.
const LIVE_RECORDINGS_COUNT_QUERY = hogql`
    SELECT count()
    FROM (
        SELECT session_id
        FROM raw_session_replay_events
        WHERE _timestamp >= now() - INTERVAL 5 MINUTE
            AND min_first_timestamp >= now() - INTERVAL 1 DAY
        GROUP BY session_id
        HAVING max(is_deleted) = 0
    )`

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface liveRecordingsCountLogicValues {
    activeRecordings: number | null
    activeRecordingsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface liveRecordingsCountLogicActions {
    loadActiveRecordings: () => any
    loadActiveRecordingsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadActiveRecordingsSuccess: (
        activeRecordings: number | null,
        payload?: any
    ) => {
        activeRecordings: number | null
        payload?: any
    }
}

export type liveRecordingsCountLogicType = MakeLogicType<
    liveRecordingsCountLogicValues,
    liveRecordingsCountLogicActions
>

export const liveRecordingsCountLogic = kea<liveRecordingsCountLogicType>([
    path(['scenes', 'session-recordings', 'components', 'liveRecordingsCountLogic']),
    loaders(({ values }) => ({
        activeRecordings: [
            null as number | null,
            {
                loadActiveRecordings: async () => {
                    // A failed poll keeps the last count instead of toasting every interval.
                    try {
                        // The default refresh mode would serve a cached count for up to 5 minutes.
                        const response = await api.queryHogQL<[number][]>(LIVE_RECORDINGS_COUNT_QUERY, QUERY_TAGS, {
                            refresh: 'force_blocking',
                        })
                        return response.results[0]?.[0] ?? 0
                    } catch {
                        return values.activeRecordings
                    }
                },
            },
        ],
    })),
    events(({ actions, cache }) => ({
        afterMount: () => {
            cache.disposables.add(() => {
                actions.loadActiveRecordings()
                const intervalId = setInterval(() => actions.loadActiveRecordings(), POLL_INTERVAL_MS)
                return () => clearInterval(intervalId)
            }, 'pollInterval')
        },
    })),
])
