import { MakeLogicType, actions, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { SessionRecordingPlaylistLogicProps, sessionRecordingsPlaylistLogic } from './sessionRecordingsPlaylistLogic'

export type ReplayListSegment = 'picks' | 'recordings' | 'collections'
export type ReplayListSegmentSource = 'user' | 'person-filter'
export type ReplayListPicksMode = 'picks' | 'recordings' | null

// A column built without its list, as the tests and findMounted callers do, listens to nothing.
const listActionType = (props: ReplayListColumnLogicProps, action: 'filterByPerson'): string =>
    props.playlistLogicProps
        ? sessionRecordingsPlaylistLogic(props.playlistLogicProps).actionTypes[action]
        : `unbound.${action}`

export interface ReplayListColumnLogicProps {
    logicKey: string
    /** The list this column belongs to, so a person filter from the player lands on its recordings. */
    playlistLogicProps?: SessionRecordingPlaylistLogicProps
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayListColumnLogicValues {
    effectiveSegmentFor: (picksMode: ReplayListPicksMode) => ReplayListSegment
    openCollectionShortId: string | null
    segment: ReplayListSegment | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayListColumnLogicActions {
    closeCollection: () => {
        value: true
    }
    dropSegmentChoice: () => {
        value: true
    }
    openCollection: (shortId: string) => {
        shortId: string
    }
    setSegment: (
        segment: ReplayListSegment,
        source?: ReplayListSegmentSource
    ) => {
        segment: ReplayListSegment
        source: ReplayListSegmentSource
    }
    settleSegment: (picksMode: ReplayListPicksMode) => {
        picksMode: ReplayListPicksMode
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface replayListColumnLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        effectiveSegmentFor: (
            segment: ReplayListSegment | null
        ) => (picksMode: ReplayListPicksMode) => ReplayListSegment
    }
}

export type replayListColumnLogicType = MakeLogicType<
    replayListColumnLogicValues,
    replayListColumnLogicActions,
    ReplayListColumnLogicProps,
    replayListColumnLogicMeta
>

export const replayListColumnLogic = kea<replayListColumnLogicType>([
    path((key) => ['scenes', 'session-recordings', 'playlist', 'replayListColumnLogic', key]),
    props({} as ReplayListColumnLogicProps),
    key((props) => props.logicKey),
    actions({
        setSegment: (segment: ReplayListSegment, source: ReplayListSegmentSource = 'user') => ({ segment, source }),
        // Or the choice resurfaces on a later recording.
        dropSegmentChoice: true,
        settleSegment: (picksMode: ReplayListPicksMode) => ({ picksMode }),
        openCollection: (shortId: string) => ({ shortId }),
        closeCollection: true,
    }),
    reducers({
        // Null until the viewer picks one, so the picks logic keeps deciding where a fresh page lands.
        segment: [
            null as ReplayListSegment | null,
            { setSegment: (_, { segment }) => segment, dropSegmentChoice: () => null },
        ],
        openCollectionShortId: [
            null as string | null,
            {
                openCollection: (_, { shortId }) => shortId,
                closeCollection: () => null,
                setSegment: () => null,
            },
        ],
    }),
    selectors({
        effectiveSegmentFor: [
            (s) => [s.segment],
            (segment: ReplayListSegment | null) =>
                (picksMode: ReplayListPicksMode): ReplayListSegment => {
                    const chosen = segment ?? picksMode ?? 'recordings'
                    return chosen === 'picks' && picksMode === null ? 'recordings' : chosen
                },
        ],
    }),
    listeners(({ actions, values, props }) => ({
        [listActionType(props, 'filterByPerson')]: ({ personUUID }: { personUUID: string | null }) => {
            if (personUUID) {
                actions.setSegment('recordings', 'person-filter')
            }
        },
        setSegment: ({ segment, source }) => {
            posthog.capture('session recording list segment changed', { segment, source })
        },
        settleSegment: ({ picksMode }) => {
            if (values.segment === 'picks' && picksMode === null) {
                actions.dropSegmentChoice()
            }
        },
    })),
])
