export const replayLayoutFeedbackLogic = kea<replayLayoutFeedbackLogicType>([
    path(['scenes', 'session-recordings', 'playlist', 'replayLayoutFeedbackLogic']),
    connect(() => ({
        values: [playerSettingsLogic, ['replayLayout', 'canOverrideLayout'], featureFlagLogic, ['featureFlags']],
        actions: [playerSettingsLogic, ['setPreferClassicReplayLayout']],
    })),
    actions({
        replayPageOpened: true,
        recordNewLayoutVisitDay: (day: string) => ({ day }),
        switchLayout: (preferClassic: boolean, source: ReplayLayoutSwitchSource) => ({ preferClassic, source }),
        recordingEnded: true,
        markSwitchBackSurveyShown: true,
        markFeedbackPromptShown: true,
    }),
    reducers({
        firstNewLayoutDay: [
            null as string | null,
            { persist: true },
            { recordNewLayoutVisitDay: (state, { day }) => state ?? day },
        ],
        lastNewLayoutDay: [null as string | null, { persist: true }, { recordNewLayoutVisitDay: (_, { day }) => day }],
        newLayoutVisitDays: [0, { persist: true }, { recordNewLayoutVisitDay: (state) => state + 1 }],
        switchBackSurveyShown: [false, { persist: true }, { markSwitchBackSurveyShown: () => true }],
        feedbackPromptShown: [false, { persist: true }, { markFeedbackPromptShown: () => true }],
    }),
    selectors({
        layoutEventProperties: [
            (s) => [s.featureFlags, s.replayLayout, s.newLayoutVisitDays, s.firstNewLayoutDay],
            (
                featureFlags: FeatureFlagsSet,
                replayLayout: ReplayLayout,
                newLayoutVisitDays: number,
                firstNewLayoutDay: string | null
            ): Properties => ({
                replay_layout: replayLayout,
                replay_layout_arm: peekFeatureFlag(featureFlags, FEATURE_FLAGS.REPLAY_WATCH_LAYOUT) ?? null,
                new_layout_visit_days: newLayoutVisitDays,
                days_since_first_new_layout: firstNewLayoutDay
                    ? dayjs().startOf('day').diff(dayjs(firstNewLayoutDay), 'day')
                    : null,
            }),
        ],
    }),
    listeners(({ actions, values }) => ({
        replayPageOpened: () => {
            if (!isNewReplayLayout(values.replayLayout) || values.canOverrideLayout) {
                return
            }
            const today = dayjs().format('YYYY-MM-DD')
            if (today !== values.lastNewLayoutDay) {
                actions.recordNewLayoutVisitDay(today)
            }
        },
        switchLayout: ({ preferClassic, source }) => {
            actions.setPreferClassicReplayLayout(preferClassic)
            posthog.capture('session recording layout changed', {
                ...values.layoutEventProperties,
                layout: preferClassic ? 'classic' : 'watch',
                source,
            })
            if (preferClassic && !values.switchBackSurveyShown) {
                showSurvey(
                    REPLAY_LAYOUT_SWITCH_BACK_SURVEY_ID,
                    { ...values.layoutEventProperties, source },
                    actions.markSwitchBackSurveyShown
                )
            }
        },
        recordingEnded: () => {
            if (feedbackPromptDue(values)) {
                showSurvey(
                    REPLAY_LAYOUT_FEEDBACK_SURVEY_ID,
                    { ...values.layoutEventProperties, trigger: 'visit_day_prompt' },
                    actions.markFeedbackPromptShown
                )
            }
        },
    })),
    subscriptions({
        replayLayout: (replayLayout: ReplayLayout) => {
            posthog.register_for_session({ replay_layout: replayLayout })
        },
    }),
])
