import posthog, { DisplaySurveyType, type Properties } from 'posthog-js'

import { FEATURE_FLAGS, REPLAY_LAYOUT_FEEDBACK_SURVEY_ID, REPLAY_LAYOUT_SWITCH_BACK_SURVEY_ID } from 'lib/constants'
import { dayjs } from 'lib/dayjs'
import { FeatureFlagsSet, featureFlagLogic, peekFeatureFlag } from 'lib/logic/featureFlagLogic'
import { playerSettingsLogic } from 'scenes/session-recordings/player/playerSettingsLogic'

import { ReplayLayout, isNewReplayLayout } from './replayLayout'

export type ReplayLayoutSwitchSource = 'header_switch' | 'layout_menu'

export const FEEDBACK_PROMPT_VISIT_DAYS = 5

export interface FeedbackPromptState {
    replayLayout: ReplayLayout
    canOverrideLayout: boolean
    newLayoutVisitDays: number
    feedbackPromptShown: boolean
    switchBackSurveyShown: boolean
}

export function feedbackPromptDue(state: FeedbackPromptState): boolean {
    return (
        isNewReplayLayout(state.replayLayout) &&
        !state.canOverrideLayout &&
        state.newLayoutVisitDays >= FEEDBACK_PROMPT_VISIT_DAYS &&
        !state.feedbackPromptShown &&
        !state.switchBackSurveyShown
    )
}

function showSurvey(surveyId: string, properties: Properties, onShown: () => void): void {
    if (!surveyId) {
        return
    }
    posthog.getSurveys((surveys) => {
        if (!surveys.some((survey) => survey.id === surveyId)) {
            return
        }
        posthog.displaySurvey(surveyId, {
            displayType: DisplaySurveyType.Popover,
            ignoreConditions: true,
            ignoreDelay: true,
            properties,
        })
        onShown()
    })
}

