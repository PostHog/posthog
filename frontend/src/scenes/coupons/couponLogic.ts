export type couponLogicType = MakeLogicType<couponLogicValues, couponLogicActions, CouponLogicProps, couponLogicMeta>

export const couponLogic = kea<couponLogicType>([
    path(['scenes', 'coupons', 'couponLogic']),
    props({} as CouponLogicProps),
    connect(() => ({
        values: [
            userLogic,
            ['user'],
            organizationLogic,
            ['currentOrganization', 'isAdminOrOwner'],
            billingLogic,
            ['billing', 'billingLoading'],
        ],
        actions: [billingLogic, ['loadBillingSuccess'], organizationLogic, ['loadCurrentOrganizationSuccess']],
    })),
    actions({
        setClaimed: (claimed: boolean) => ({ claimed }),
        setClaimedDetails: (details: BillingCouponClaimResponseApi) => ({ details }),
    }),
    loaders(({ values }) => ({
        couponsOverview: [
            null as BillingCouponsOverviewResponseApi | null,
            {
                loadCouponsOverview: async () => {
                    // The loadCurrentOrganizationSuccess listener loads the overview once the organization arrives.
                    const organizationId = values.currentOrganization?.id
                    if (!organizationId || values.isAdminOrOwner === false) {
                        return null
                    }
                    return await billingOrganizationCouponsOverviewRetrieve(organizationId)
                },
            },
        ],
    })),
    reducers({
        claimed: [false, { setClaimed: (_, { claimed }) => claimed }],
        claimedDetails: [
            null as BillingCouponClaimResponseApi | null,
            { setClaimedDetails: (_, { details }) => details },
        ],
    }),
    selectors({
        getClaimedCouponForCampaign: [
            (s) => [s.couponsOverview],
            (couponsOverview: BillingCouponsOverviewResponseApi | null) =>
                (campaignSlug: string): BillingClaimedCouponApi | null => {
                    return couponsOverview?.claimed_coupons?.find((c) => c.campaign_slug === campaignSlug) || null
                },
        ],
        activeCoupons: [
            (s) => [s.couponsOverview],
            (couponsOverview: BillingCouponsOverviewResponseApi | null): BillingClaimedCouponApi[] => {
                return couponsOverview?.claimed_coupons?.filter((c) => c.status === 'claimed') ?? []
            },
        ],
    }),
    forms(({ values, actions, props }) => ({
        coupon: {
            defaults: {
                code: '',
                organization_name: values.currentOrganization?.name || '',
            } as CouponFormValues,
            errors: ({ code }) => {
                // Cheat codes have no paid plan requirement, so the billing service decides eligibility.
                if (cheatCodeCampaignSlug(code)) {
                    return {}
                }
                if (!values.billingLoading && !values.billing?.has_active_subscription) {
                    return {
                        _form: 'You need to be on a paid plan before claiming this coupon',
                    }
                }
                return {
                    code: !code ? 'Please enter a coupon code' : undefined,
                }
            },
            submit: async (formValues: CouponFormValues) => {
                const cheatCodeSlug = cheatCodeCampaignSlug(formValues.code)
                if (cheatCodeSlug) {
                    // Typing the code claims it through the global shortcut, as in GTA: San Andreas, so the
                    // form never sends it. A paste skips the shortcut, so that case gets a nudge to type it.
                    const typed = cheatCodeTypedRecently()
                    if (!typed) {
                        lemonToast.info(
                            `Type ${cheatCodeSlug.toUpperCase()} out letter by letter. Pasting it doesn't count.`
                        )
                    }
                    posthog.capture('billing cheat code submitted as coupon', {
                        campaign: props.campaign,
                        campaign_slug: cheatCodeSlug,
                        typed,
                    })
                    actions.setCouponValue('code', '')
                    return
                }
                try {
                    const res = await billingOrganizationCouponsClaimCreate(
                        billingOrganizationId(values.currentOrganization),
                        { code: formValues.code }
                    )
                    actions.setClaimed(true)
                    actions.setClaimedDetails(res)
                    actions.loadCouponsOverview()
                    posthog.capture('billing coupon claimed', {
                        campaign: props.campaign,
                        code: formValues.code,
                    })
                } catch (error: any) {
                    lemonToast.error(error.detail || 'Failed to claim coupon')
                    posthog.capture('billing coupon claim failed', {
                        campaign: props.campaign,
                        code: formValues.code,
                        error: error.detail || 'Unknown error',
                    })
                    throw error
                }
            },
        },
    })),
    listeners(({ values, actions }) => ({
        loadBillingSuccess: () => {
            // kea-forms errors() is a selector that only recalculates when form state changes.
            // Since we depend on external billing state, we force recalculation by re-setting a form value.
            actions.setCouponValue('code', values.coupon.code)
        },
        loadCurrentOrganizationSuccess: () => {
            if (!values.couponsOverview && values.isAdminOrOwner) {
                actions.loadCouponsOverview()
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadCouponsOverview()
    }),
])
