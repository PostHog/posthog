import { MakeLogicType, connect, kea, key, path, props, selectors } from 'kea'

import { INSTANTLY_AVAILABLE_PROPERTIES } from 'lib/constants'
import {
    EventIngestionRestriction,
    RestrictionType,
    eventIngestionRestrictionLogic,
} from 'lib/logic/eventIngestionRestrictionLogic'
import { stringifyWithBigInts } from 'lib/utils/json'
import { teamLogic } from 'scenes/teamLogic'

import { AnyPropertyFilter, PropertyFilterType, TeamPublicType, TeamType } from '~/types'

export interface FeatureFlagPersonlessWarningLogicProps {
    properties: AnyPropertyFilter[]
}

export type PersonlessReason = 'project-opt-out' | 'ingestion-restriction'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagPersonlessWarningLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    eventIngestionRestrictions: EventIngestionRestriction[] // eventIngestionRestrictionLogic
    personlessReason: PersonlessReason | null
    storedPropertyKeys: string[]
    targetsCohort: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagPersonlessWarningLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        personlessReason: (
            currentTeam: TeamPublicType | TeamType | null,
            eventIngestionRestrictions: EventIngestionRestriction[]
        ) => PersonlessReason | null
        storedPropertyKeys: (properties: AnyPropertyFilter[]) => string[]
        targetsCohort: (properties: AnyPropertyFilter[]) => boolean
    }
}

export type featureFlagPersonlessWarningLogicType = MakeLogicType<
    featureFlagPersonlessWarningLogicValues,
    {},
    FeatureFlagPersonlessWarningLogicProps,
    featureFlagPersonlessWarningLogicMeta
>

export const featureFlagPersonlessWarningLogic = kea<featureFlagPersonlessWarningLogicType>([
    path(['scenes', 'feature-flags', 'featureFlagPersonlessWarningLogic']),
    props({} as FeatureFlagPersonlessWarningLogicProps),
    key((props) => stringifyWithBigInts(props.properties)),
    connect(() => ({
        values: [teamLogic, ['currentTeam'], eventIngestionRestrictionLogic, ['eventIngestionRestrictions']],
    })),

    selectors({
        personlessReason: [
            (s) => [s.currentTeam, s.eventIngestionRestrictions],
            (
                currentTeam: TeamPublicType | TeamType | null,
                eventIngestionRestrictions: EventIngestionRestriction[]
            ): PersonlessReason | null => {
                if (
                    currentTeam &&
                    'person_processing_opt_out' in currentTeam &&
                    currentTeam.person_processing_opt_out
                ) {
                    return 'project-opt-out'
                }
                if (
                    eventIngestionRestrictions.some(
                        (restriction) => restriction.restriction_type === RestrictionType.SKIP_PERSON_PROCESSING
                    )
                ) {
                    return 'ingestion-restriction'
                }
                return null
            },
        ],

        storedPropertyKeys: [
            (_, p) => [p.properties],
            (properties: AnyPropertyFilter[]): string[] => {
                const keys = properties
                    .filter(
                        (property) =>
                            property.type === PropertyFilterType.Person &&
                            !!property.key &&
                            !INSTANTLY_AVAILABLE_PROPERTIES.includes(property.key)
                    )
                    .map((property) => String(property.key))
                return [...new Set(keys)]
            },
        ],

        targetsCohort: [
            (_, p) => [p.properties],
            (properties: AnyPropertyFilter[]): boolean =>
                properties.some((property) => property.type === PropertyFilterType.Cohort),
        ],
    }),
])
