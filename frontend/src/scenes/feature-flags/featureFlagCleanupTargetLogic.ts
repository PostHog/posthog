import { MakeLogicType, afterMount, connect, kea, key, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { projectLogic } from 'scenes/projectLogic'

import { featureFlagsCleanupTargetRetrieve } from 'products/feature_flags/frontend/generated/api'
import type { FeatureFlagCleanupTargetApi } from 'products/feature_flags/frontend/generated/api.schemas'

import type { FeatureFlagsSet } from '../../lib/logic/featureFlagLogic'

export interface FeatureFlagCleanupTargetLogicProps {
    featureFlagId: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagCleanupTargetLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentProjectId: number | null // projectLogic
    cleanupTarget: FeatureFlagCleanupTargetApi | null
    cleanupTargetLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagCleanupTargetLogicActions {
    loadCleanupTarget: () => any
    loadCleanupTargetFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadCleanupTargetSuccess: (
        cleanupTarget: FeatureFlagCleanupTargetApi,
        payload?: any
    ) => {
        cleanupTarget: FeatureFlagCleanupTargetApi
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagCleanupTargetLogicMeta {
    key: number
}

export type featureFlagCleanupTargetLogicType = MakeLogicType<
    featureFlagCleanupTargetLogicValues,
    featureFlagCleanupTargetLogicActions,
    FeatureFlagCleanupTargetLogicProps,
    featureFlagCleanupTargetLogicMeta
>

export const featureFlagCleanupTargetLogic = kea<featureFlagCleanupTargetLogicType>([
    props({} as FeatureFlagCleanupTargetLogicProps),
    key((props) => props.featureFlagId),
    path((key) => ['scenes', 'feature-flags', 'featureFlagCleanupTargetLogic', key]),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']],
    })),
    loaders(({ props, values }) => ({
        cleanupTarget: [
            null as FeatureFlagCleanupTargetApi | null,
            {
                loadCleanupTarget: async () =>
                    await featureFlagsCleanupTargetRetrieve(String(values.currentProjectId), props.featureFlagId),
            },
        ],
    })),
    afterMount(({ actions, props, values }) => {
        // The cleanup PR runs as a Code task, so the target is only needed for users with Code access.
        if (props.featureFlagId && values.featureFlags[FEATURE_FLAGS.TASKS]) {
            actions.loadCleanupTarget()
        }
    }),
])
