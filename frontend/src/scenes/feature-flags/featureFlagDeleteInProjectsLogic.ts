export const featureFlagDeleteInProjectsLogic = kea<featureFlagDeleteInProjectsLogicType>([
    path(['scenes', 'feature-flags', 'featureFlagDeleteInProjectsLogic']),
    props({} as FeatureFlagLogicProps),
    key(({ id }) => id ?? 'unknown'),
    connect((props: FeatureFlagLogicProps) => ({
        values: [featureFlagLogic(props), ['featureFlag'], organizationLogic, ['currentOrganization']],
        actions: [featureFlagLogic(props), ['loadProjectsWithCurrentFlag', 'deleteFlag']],
    })),
    actions({
        confirmDeleteInProjects: (projectIds: number[]) => ({ projectIds }),
        deleteInProjects: (projectIds: number[]) => ({ projectIds }),
        closeDeleteInProjectsResult: true,
    }),
    loaders(({ values }) => ({
        deleteInProjectsResult: [
            null as DeleteFlagInProjectsResponseApi | null,
            {
                deleteInProjects: async ({ projectIds }) =>
                    await orgFeatureFlagsDeleteInProjects(values.currentOrganization?.id ?? '', {
                        feature_flag_key: values.featureFlag.key,
                        project_ids: projectIds,
                    }),
            },
        ],
    })),
    reducers({
        deleteInProjectsResultVisible: [
            false,
            {
                deleteInProjectsSuccess: () => true,
                closeDeleteInProjectsResult: () => false,
            },
        ],
    }),
    selectors({
        projectNamesById: [
            (s) => [s.currentOrganization],
            (currentOrganization: OrganizationType | null): Record<number, string> =>
                Object.fromEntries((currentOrganization?.teams ?? []).map((team) => [team.id, team.name])),
        ],
        currentFlagDeleted: [
            (s) => [s.deleteInProjectsResult, s.featureFlag],
            (result: DeleteFlagInProjectsResponseApi | null, featureFlag: FeatureFlagType): boolean =>
                !!result?.deleted.some((item) => item.flag_id === featureFlag.id),
        ],
    }),
    listeners(({ actions, values }) => ({
        confirmDeleteInProjects: ({ projectIds }) => {
            // pinned: analytics event name, renaming breaks dashboards
            posthog.capture('feature flag delete in projects started', { project_count: projectIds.length })
            const names = projectIds.map((id) => values.projectNamesById[id] ?? `Project ${id}`)
            LemonDialog.open({
                title: `Delete this flag in ${pluralize(projectIds.length, 'project')}?`,
                description: `"${values.featureFlag.key}" will be deleted in ${names.join(', ')}. Users in those projects will no longer get this flag.`,
                primaryButton: {
                    children: 'Delete',
                    status: 'danger',
                    onClick: () => actions.deleteInProjects(projectIds),
                    'data-attr': 'feature-flag-delete-in-projects-confirm',
                },
                secondaryButton: {
                    children: 'Cancel',
                },
            })
        },
        deleteInProjectsSuccess: ({ deleteInProjectsResult }) => {
            actions.loadProjectsWithCurrentFlag()
            for (const { flag_id } of deleteInProjectsResult.deleted) {
                deleteFromTree('feature_flag', String(flag_id))
            }
            if (values.currentFlagDeleted && typeof values.featureFlag.id === 'number') {
                actions.deleteFlag(values.featureFlag.id)
            }
        },
        closeDeleteInProjectsResult: () => {
            // The page shows a flag that no longer exists, so leave it as the single delete does.
            if (values.currentFlagDeleted) {
                router.actions.push(urls.featureFlags())
            }
        },
    })),
])
