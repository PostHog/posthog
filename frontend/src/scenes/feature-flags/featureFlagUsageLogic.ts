import { LogicWrapper, MakeLogicType, actions, connect, kea, key, path, props, reducers, selectors } from 'kea'
import { actionToUrl, router, urlToAction } from 'kea-router'

import { urls } from 'scenes/urls'

import { Noun, groupsModel } from '~/models/groupsModel'
import { DateRange } from '~/queries/schema/schema-general'
import { FeatureFlagType } from '~/types'

import { featureFlagLogic } from './featureFlagLogic'
import {
    DEFAULT_USAGE_DATE_RANGE,
    FlagUsageChart,
    FlagUsageQueryOptions,
    buildEnrichedUsageCharts,
    buildFlagCalledTotalVolumeChart,
    buildFlagCalledUniqueCallersChart,
} from './featureFlagUsageQueries'

// The Usage tab only renders for persisted flags, so unlike featureFlagLogic this
// logic never mounts for 'new'/'link' ids.
export interface FeatureFlagUsageLogicProps {
    id: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagUsageLogicValues {
    featureFlag: FeatureFlagType // featureFlagLogic
    aggregationLabel: (groupTypeIndex: number | null | undefined, deferToUserWording?: boolean) => Noun // groupsModel
    dateRange: DateRange
    usageCharts: FlagUsageChart[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagUsageLogicActions {
    setDates: (dateFrom: string | null, dateTo: string | null) => { dateFrom: string | null; dateTo: string | null }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagUsageLogicMeta {
    key: number
    __keaTypeGenInternalSelectorTypes: {
        usageCharts: (
            featureFlag: FeatureFlagType,
            dateRange: DateRange,
            aggregationLabel: (groupTypeIndex: number | null | undefined, deferToUserWording?: boolean) => Noun
        ) => FlagUsageChart[]
    }
}

export type featureFlagUsageLogicType = MakeLogicType<
    featureFlagUsageLogicValues,
    featureFlagUsageLogicActions,
    FeatureFlagUsageLogicProps,
    featureFlagUsageLogicMeta
>

export const featureFlagUsageLogic: LogicWrapper<featureFlagUsageLogicType> = kea<featureFlagUsageLogicType>([
    props({} as FeatureFlagUsageLogicProps),
    key(({ id }) => id),
    path((key) => ['scenes', 'feature-flags', 'featureFlagUsageLogic', key]),
    connect((props: FeatureFlagUsageLogicProps) => ({
        values: [featureFlagLogic(props), ['featureFlag'], groupsModel, ['aggregationLabel']],
    })),
    actions({
        setDates: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
    }),
    reducers({
        dateRange: [
            DEFAULT_USAGE_DATE_RANGE,
            {
                setDates: (_, { dateFrom, dateTo }) => ({ date_from: dateFrom, date_to: dateTo }),
            },
        ],
    }),
    selectors({
        usageCharts: [
            (s) => [s.featureFlag, s.dateRange, s.aggregationLabel],
            (
                featureFlag: FeatureFlagType,
                dateRange: DateRange,
                aggregationLabel: (groupTypeIndex: number | null | undefined, deferToUserWording?: boolean) => Noun
            ): FlagUsageChart[] => {
                const aggregationGroupTypeIndex = featureFlag.filters?.aggregation_group_type_index
                const options: FlagUsageQueryOptions = {
                    flagKey: featureFlag.key,
                    aggregationGroupTypeIndex,
                    callerNoun: aggregationLabel(aggregationGroupTypeIndex, true),
                    dateRange,
                }
                const charts = [buildFlagCalledTotalVolumeChart(options), buildFlagCalledUniqueCallersChart(options)]
                if (featureFlag.has_enriched_analytics) {
                    charts.push(...buildEnrichedUsageCharts(options))
                }
                return charts
            },
        ],
    }),
    actionToUrl(({ values }) => ({
        setDates: () => {
            const searchParams = { ...router.values.searchParams }
            for (const [param, value] of [
                ['date_from', values.dateRange.date_from],
                ['date_to', values.dateRange.date_to],
            ] as const) {
                if (value) {
                    searchParams[param] = value
                } else {
                    delete searchParams[param]
                }
            }
            // Replace rather than push: featureFlagLogic reloads the flag on a PUSH to this pathname.
            return [router.values.location.pathname, searchParams, router.values.hashParams, { replace: true }]
        },
    })),
    urlToAction(({ actions, props, values }) => ({
        [urls.featureFlag(props.id)]: (_, searchParams) => {
            // Absent params mean "use the default range", not "clear the range".
            if (!searchParams.date_from && !searchParams.date_to) {
                return
            }
            const dateFrom = searchParams.date_from ?? null
            const dateTo = searchParams.date_to ?? null
            if (dateFrom !== values.dateRange.date_from || dateTo !== values.dateRange.date_to) {
                actions.setDates(dateFrom, dateTo)
            }
        },
    })),
])
