export type featureFlagGuidelinesLogicType = MakeLogicType<
    featureFlagGuidelinesLogicValues,
    featureFlagGuidelinesLogicActions,
    Record<string, any>,
    featureFlagGuidelinesLogicMeta
>

export const featureFlagGuidelinesLogic = kea<featureFlagGuidelinesLogicType>([
    path(['scenes', 'feature-flags', 'featureFlagGuidelinesLogic']),

    connect(() => ({
        values: [teamLogic, ['currentTeam']],
    })),

    actions({
        setLocalEnabled: (enabled: boolean) => ({ enabled }),
        setLocalUrl: (url: string) => ({ url }),
        discardChanges: true,
    }),

    reducers({
        localEnabled: [
            false,
            {
                setLocalEnabled: (_, { enabled }) => enabled,
                loadFeatureFlagGuidelinesSuccess: (_, { featureFlagGuidelines }) =>
                    featureFlagGuidelines?.enabled ?? false,
            },
        ],
        localUrl: [
            '',
            {
                setLocalUrl: (_, { url }) => url,
                loadFeatureFlagGuidelinesSuccess: (_, { featureFlagGuidelines }) => featureFlagGuidelines?.url ?? '',
            },
        ],
    }),

    loaders(({ values }) => ({
        featureFlagGuidelines: [
            null as FeatureFlagGuidelinesResponse | null,
            {
                loadFeatureFlagGuidelines: async () => {
                    const teamId = values.currentTeam?.id
                    if (!teamId) {
                        return null
                    }
                    return await fetchFeatureFlagGuidelines(teamId)
                },

                saveFeatureFlagGuidelines: async () => {
                    const teamId = values.currentTeam?.id
                    if (!teamId) {
                        throw new Error('No team selected')
                    }

                    return (await api.put(`/api/projects/${teamId}/feature_flag_guidelines/`, {
                        enabled: values.localEnabled,
                        url: values.localUrl,
                    })) as FeatureFlagGuidelinesResponse
                },
            },
        ],
    })),

    listeners(({ actions, values }) => ({
        saveFeatureFlagGuidelinesSuccess: () => {
            lemonToast.success('Feature flag guidelines saved')
        },
        discardChanges: () => {
            const saved = values.featureFlagGuidelines
            actions.setLocalEnabled(saved?.enabled ?? false)
            actions.setLocalUrl(saved?.url ?? '')
        },
    })),

    selectors({
        isEnabled: [(s) => [s.localEnabled], (localEnabled: boolean): boolean => localEnabled],
        url: [(s) => [s.localUrl], (localUrl: string): string => localUrl],
        hasChanges: [
            (s) => [s.localEnabled, s.localUrl, s.featureFlagGuidelines],
            (localEnabled: boolean, localUrl: string, saved: FeatureFlagGuidelinesResponse | null): boolean => {
                if (!saved) {
                    return false
                }
                return localEnabled !== saved.enabled || localUrl !== saved.url
            },
        ],
    }),

    afterMount(({ actions }) => {
        actions.loadFeatureFlagGuidelines()
    }),
])
