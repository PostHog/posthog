import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { teamLogic } from 'scenes/teamLogic'

import type { TeamPublicType, TeamType } from '../../types'

export interface FeatureFlagGuidelinesResponse {
    enabled: boolean
    url: string
}

export async function fetchFeatureFlagGuidelines(teamId: number): Promise<FeatureFlagGuidelinesResponse> {
    return await api.get(`/api/projects/${teamId}/feature_flag_guidelines/`)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface featureFlagGuidelinesLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    featureFlagGuidelines: FeatureFlagGuidelinesResponse | null
    featureFlagGuidelinesLoading: boolean
    hasChanges: boolean
    isEnabled: boolean
    localEnabled: boolean
    localUrl: string
    url: string
}

