export const guidedOnboardingLogic = kea<guidedOnboardingLogicType>([
    path(['scenes', 'onboarding', 'flows', 'guided', 'guidedOnboardingLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
        actions: [teamLogic, ['updateCurrentTeam']],
    })),
    actions({
        setGuidance: (guidance: Guidance) => ({ guidance }),
        setProjectName: (projectName: string) => ({ projectName }),
        togglePlatform: (platform: Platform) => ({ platform }),
        setIndustry: (industry: Industry) => ({ industry }),
        setCustomIndustry: (customIndustry: string) => ({ customIndustry }),
        setWebsiteUrl: (websiteUrl: string) => ({ websiteUrl }),
        submitWebsiteUrl: true,
        setFocusKey: (focusKey: string) => ({ focusKey }),
        setCustomFocus: (customFocus: string) => ({ customFocus }),
        addTrackedEvent: (eventName: string) => ({ eventName }),
        removeTrackedEvent: (eventName: string) => ({ eventName }),
        pollEvents: true,
        setSeenEvents: (latestEvent: SeenEvent | null, trackedLastSeen: SeenEvent[]) => ({
            latestEvent,
            trackedLastSeen,
        }),
        setTarget: (target: number) => ({ target }),
        setInstallMethod: (installMethod: InstallMethod) => ({ installMethod }),
        next: true,
        /** Clears the answers given on `steps`, so a step reached again after going back starts fresh. */
        resetAnswers: (steps: GuidedStep[], defaultEvents: string[]) => ({ steps, defaultEvents }),
        back: true,
        finish: true,
    }),
    reducers({
        guidance: [null as Guidance | null, { setGuidance: (_, { guidance }) => guidance }],
        projectName: [
            null as string | null,
            {
                setProjectName: (_, { projectName }) => projectName,
                resetAnswers: (state, { steps }) => (steps.includes('project') ? null : state),
            },
        ],
        platforms: [
            [] as Platform[],
            {
                togglePlatform: (platforms, { platform }) =>
                    platforms.includes(platform) ? platforms.filter((p) => p !== platform) : [...platforms, platform],
                resetAnswers: (state, { steps }) => (steps.includes('platform') ? [] : state),
            },
        ],
        industry: [
            null as Industry | null,
            {
                setIndustry: (_, { industry }) => industry,
                resetAnswers: (state, { steps }) => (steps.includes('industry') ? null : state),
            },
        ],
        customIndustry: [
            '',
            {
                setCustomIndustry: (_, { customIndustry }) => customIndustry,
                resetAnswers: (state, { steps }) => (steps.includes('industry') ? '' : state),
            },
        ],
        customFocus: [
            '',
            {
                setCustomFocus: (_, { customFocus }) => customFocus,
                resetAnswers: (state, { steps }) => (steps.includes('focus') ? '' : state),
            },
        ],
        websiteUrl: [
            null as string | null,
            {
                setWebsiteUrl: (_, { websiteUrl }) => websiteUrl,
                resetAnswers: (state, { steps }) => (steps.includes('website') ? null : state),
            },
        ],
        focusKey: [
            null as string | null,
            {
                setFocusKey: (_, { focusKey }) => focusKey,
                // An industry-specific goal may not exist for the new industry.
                setIndustry: () => null,
                resetAnswers: (state, { steps }) => (steps.includes('focus') ? null : state),
            },
        ],
        trackedEvents: [
            [] as string[],
            {
                setFocusKey: (_, { focusKey }) => FOCUS_OPTIONS.find((option) => option.key === focusKey)?.events ?? [],
                addTrackedEvent: (events, { eventName }) => {
                    const name = eventName.trim()
                    return name && !events.includes(name) ? [...events, name] : events
                },
                removeTrackedEvent: (events, { eventName }) => events.filter((event) => event !== eventName),
                resetAnswers: (events, { steps, defaultEvents }) =>
                    steps.includes('focus') ? [] : steps.includes('events') ? defaultEvents : events,
            },
        ],
        latestEvent: [null as SeenEvent | null, { setSeenEvents: (_, { latestEvent }) => latestEvent }],
        /** Event name to when it was last seen, for the events on the user's list. */
        trackedLastSeen: [
            {} as Record<string, string>,
            {
                setSeenEvents: (lastSeen, { trackedLastSeen }) => ({
                    ...lastSeen,
                    ...Object.fromEntries(trackedLastSeen.map(({ event, timestamp }) => [event, timestamp])),
                }),
            },
        ],
        target: [
            null as number | null,
            {
                setTarget: (_, { target }) => target,
                setFocusKey: () => null,
                resetAnswers: (state, { steps }) => (steps.includes('goal') ? null : state),
            },
        ],
        installMethod: [
            'wizard' as InstallMethod,
            {
                setInstallMethod: (_, { installMethod }) => installMethod,
                resetAnswers: (state, { steps }) => (steps.includes('install') ? 'wizard' : state),
            },
        ],
        stepIndex: [0, { next: (index) => index + 1, back: (index) => Math.max(0, index - 1) }],
    }),
    selectors({
        steps: [
            (s) => [s.guidance, s.focusKey, s.platforms],
            (guidance: Guidance | null, focusKey: string | null, platforms: Platform[]): GuidedStep[] =>
                guidance === 'self'
                    ? SELF_STEPS
                    : GUIDED_STEPS.filter(
                          (step) =>
                              // A goal the user typed has no target to set.
                              (step !== 'goal' || focusKey !== CUSTOM_FOCUS_KEY) &&
                              // Web analytics needs the website's URL, so only web apps get this step.
                              (step !== 'website' || platforms.includes('web'))
                      ),
        ],
        step: [
            (s) => [s.steps, s.stepIndex],
            (steps: GuidedStep[], stepIndex: number): GuidedStep => steps[Math.min(stepIndex, steps.length - 1)],
        ],
        // Both start empty: onboarding never shows values saved on the project earlier.
        resolvedProjectName: [(s) => [s.projectName], (projectName: string | null): string => projectName ?? ''],
        resolvedWebsiteUrl: [(s) => [s.websiteUrl], (websiteUrl: string | null): string => websiteUrl ?? ''],
        websiteUrlError: [
            (s) => [s.resolvedWebsiteUrl],
            (url: string): string | undefined =>
                url.trim() ? validateProposedUrl(url.trim(), [], false, false) : undefined,
        ],
        displayName: [(s) => [s.resolvedProjectName], (name: string): string => name.trim() || 'your product'],
        focus: [
            (s) => [s.focusKey, s.customFocus],
            (focusKey: string | null, customFocus: string): FocusOption | null =>
                focusKey === CUSTOM_FOCUS_KEY
                    ? customFocusOption(customFocus.trim())
                    : (FOCUS_OPTIONS.find((option) => option.key === focusKey) ?? null),
        ],
        resolvedTarget: [
            (s) => [s.target, s.focus],
            (target: number | null, focus: FocusOption | null): number => target ?? focus?.defaultTarget ?? 10,
        ],
        products: [
            (s) => [s.focus, s.platforms],
            (focus: FocusOption | null, platforms: Platform[]): ProductKey[] => {
                const products = focus?.products ?? [ProductKey.PRODUCT_ANALYTICS]
                return platforms.includes('web') && !products.includes(ProductKey.WEB_ANALYTICS)
                    ? [...products, ProductKey.WEB_ANALYTICS]
                    : products
            },
        ],
        progress: [
            (s) => [s.stepIndex, s.steps],
            (stepIndex: number, steps: GuidedStep[]): number => progressFor(stepIndex, steps.length),
        ],
    }),
    listeners(({ actions, values }) => ({
        setGuidance: () => actions.next(),
        setIndustry: ({ industry }) => {
            if (industry !== 'other') {
                actions.next()
            }
        },
        back: () => {
            // Runs after the reducer, so `stepIndex` is the step the user returned to.
            actions.resetAnswers(values.steps.slice(values.stepIndex + 1), values.focus?.events ?? [])
        },
        next: () => {
            // Runs after the reducer, so `platform` means the project step was just left.
            if (values.step === 'platform' && values.projectName !== null) {
                const name = values.resolvedProjectName.trim()
                if (name && name !== values.currentTeam?.name) {
                    actions.updateCurrentTeam({ name })
                }
            }
        },
        submitWebsiteUrl: () => {
            const url = values.resolvedWebsiteUrl.trim()
            if (!url || values.websiteUrlError) {
                return
            }
            const existing = (values.currentTeam as TeamType | null)?.app_urls ?? []
            if (!existing.includes(url)) {
                actions.updateCurrentTeam({ app_urls: [url, ...existing] })
            }
            actions.next()
        },
        pollEvents: async (_, breakpoint) => {
            const query = (sql: ReturnType<typeof hogql>): Promise<SeenEvent[]> =>
                api
                    .query<HogQLQuery>(
                        { kind: NodeKind.HogQLQuery, query: sql, tags: { productKey: ProductKey.PRODUCT_ANALYTICS } },
                        { refresh: 'force_blocking' }
                    )
                    .then((response) =>
                        (response.results ?? []).map(([event, timestamp]) => ({
                            event: String(event),
                            timestamp: String(timestamp),
                        }))
                    )
            try {
                const [latest, tracked] = await Promise.all([
                    query(
                        hogql`SELECT event, timestamp FROM events WHERE timestamp > now() - INTERVAL 7 DAY ORDER BY timestamp DESC LIMIT 1`
                    ),
                    values.trackedEvents.length > 0
                        ? query(
                              hogql`SELECT event, max(timestamp) FROM events WHERE event IN ${values.trackedEvents} AND timestamp > now() - INTERVAL 7 DAY GROUP BY event`
                          )
                        : Promise.resolve([]),
                ])
                breakpoint()
                actions.setSeenEvents(latest[0] ?? null, tracked)
            } catch {
                // The install step polls again on its next tick, so a failed check only delays the update.
            }
        },
        finish: () => {
            const completed = { ...values.currentTeam?.has_completed_onboarding_for }
            for (const product of values.products) {
                completed[product] = true
            }
            actions.updateCurrentTeam({ has_completed_onboarding_for: completed })
            router.actions.push(urls.projectHomepage())
        },
    })),
])
