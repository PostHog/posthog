export type onboardingEventUsageLogicType = MakeLogicType<
    onboardingEventUsageLogicValues,
    onboardingEventUsageLogicActions
>

export const onboardingEventUsageLogic = kea<onboardingEventUsageLogicType>([
    path(['scenes', 'onboarding', 'onboardingEventUsageLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),
    actions({
        reportOnboardingStepViewed: (stepId: SelfDrivingOnboardingStepId) => ({ stepId }),
        reportOnboardingGoalSelected: (goal: string) => ({ goal }),
        reportOnboardingUseCaseSelected: (
            useCase: string,
            recommendedProducts: readonly string[],
            properties?: OnboardingEventProperties
        ) => ({
            useCase,
            recommendedProducts,
            properties,
        }),
        reportOnboardingInstallModeSelected: (mode: 'cloud' | 'local' | 'manual') => ({ mode }),
        reportOnboardingSelfDrivingExplainerClicked: (stepKey: SelfDrivingOnboardingStepId) => ({ stepKey }),
        reportOnboardingInstallVerified: () => ({}),
        reportOnboardingPlanSelected: (plan: 'free' | 'pay_as_you_go') => ({ plan }),
        reportOnboardingCloudRunQueued: (props: { taskId: string; runId: string; repository: string }) => props,
        reportOnboardingCloudRunCompleted: (props: {
            taskId: string
            runId: string
            status: 'completed' | 'failed' | 'cancelled'
            durationSeconds: number | null
            prOpened: boolean
            prUrl: string | null
        }) => props,
        reportWizardSyncExpanded: (props: { runKey: string; mode: 'cloud' | 'local'; phase: string }) => props,
        reportWizardSyncMinimized: (props: { runKey: string; mode: 'cloud' | 'local'; phase: string }) => props,
        reportWizardSyncRestored: (props: { runKey: string; mode: 'cloud' | 'local'; phase: string }) => props,
        reportWizardSyncRunDismissed: (props: {
            runKey: string
            mode: 'cloud' | 'local'
            phase: string
            elapsedSeconds: number
        }) => props,
        reportWizardSyncHandoffShown: (props: {
            runKey: string
            mode: 'cloud' | 'local'
            surface: 'inline' | 'fab'
            prOpened: boolean
        }) => props,
        reportWizardSyncHandoffDocOpened: (props: {
            runKey: string
            mode: 'cloud' | 'local'
            trigger: 'auto' | 'button'
        }) => props,
    }),
    listeners(({ values }) => ({
        reportOnboardingStepViewed: ({ stepId }) => {
            posthog.capture('onboarding step viewed', {
                step_key: stepId,
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        reportOnboardingGoalSelected: ({ goal }) => {
            posthog.capture('onboarding goal selected', {
                goal,
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        reportOnboardingUseCaseSelected: ({ useCase, recommendedProducts, properties }) => {
            posthog.capture('onboarding use case selected', {
                use_case: useCase,
                recommended_products: recommendedProducts,
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
                ...properties,
            })
        },
        reportOnboardingInstallModeSelected: ({ mode }) => {
            posthog.capture('onboarding install mode selected', {
                mode,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportOnboardingSelfDrivingExplainerClicked: ({ stepKey }) => {
            posthog.capture('onboarding self-driving explainer clicked', {
                step_key: stepKey,
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        reportOnboardingInstallVerified: () => {
            posthog.capture('onboarding installation verified', {
                step_key: 'install',
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        reportOnboardingPlanSelected: ({ plan }) => {
            posthog.capture('onboarding plan selected', {
                plan,
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        reportOnboardingCloudRunQueued: ({ taskId, runId }) => {
            posthog.capture('onboarding cloud run queued', {
                task_id: taskId,
                run_id: runId,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportOnboardingCloudRunCompleted: ({ taskId, runId, status, durationSeconds, prOpened }) => {
            posthog.capture('onboarding cloud run completed', {
                task_id: taskId,
                run_id: runId,
                status,
                duration_seconds: durationSeconds,
                pr_opened: prOpened,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportWizardSyncExpanded: ({ runKey, mode, phase }) => {
            posthog.capture('wizard sync expanded', {
                run_key: runKey,
                mode,
                phase,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportWizardSyncMinimized: ({ runKey, mode, phase }) => {
            posthog.capture('wizard sync minimized', {
                run_key: runKey,
                mode,
                phase,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportWizardSyncRestored: ({ runKey, mode, phase }) => {
            posthog.capture('wizard sync restored', {
                run_key: runKey,
                mode,
                phase,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportWizardSyncRunDismissed: ({ runKey, mode, phase, elapsedSeconds }) => {
            posthog.capture('wizard sync run dismissed', {
                run_key: runKey,
                mode,
                phase,
                elapsed_seconds: elapsedSeconds,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportWizardSyncHandoffShown: ({ runKey, mode, surface, prOpened }) => {
            if (reportedHandoffShownRuns.has(runKey)) {
                return
            }
            reportedHandoffShownRuns.add(runKey)
            posthog.capture('wizard sync handoff shown', {
                run_key: runKey,
                mode,
                surface,
                pr_opened: prOpened,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        // Opens are NOT deduped: reopening the doc through the button is real engagement, and the
        // auto trigger fires at most once per run by construction (wizardSyncUiLogic's seen keys).
        reportWizardSyncHandoffDocOpened: ({ runKey, mode, trigger }) => {
            posthog.capture('wizard sync handoff doc opened', {
                run_key: runKey,
                mode,
                trigger,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
    })),
])
