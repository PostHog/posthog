export type onboardingEventUsageLogicType = MakeLogicType<
    onboardingEventUsageLogicValues,
    onboardingEventUsageLogicActions
>

/**
 * Funnel events for the self-driving onboarding flow (v2) — a dedicated logic rather than more
 * surface on the giant `eventUsageLogic`, following `sessionRecordingEventUsageLogic`'s split.
 * Shared funnel signals (started, step completed/skipped, completed) reuse the legacy event names
 * with `version: 2`; signals the legacy flow doesn't have (step viewed, install mode, plan, cloud
 * run) get their own names.
 */
export const onboardingEventUsageLogic = kea<onboardingEventUsageLogicType>([
    path(['scenes', 'onboarding', 'onboardingEventUsageLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),
    actions({
        reportSelfDrivingOnboardingStarted: true,
        reportSelfDrivingOnboardingStepViewed: (stepId: SelfDrivingOnboardingStepId) => ({ stepId }),
        reportSelfDrivingOnboardingStepCompleted: (stepId: SelfDrivingOnboardingStepId) => ({ stepId }),
        reportSelfDrivingOnboardingStepSkipped: (stepId: SelfDrivingOnboardingStepId) => ({ stepId }),
        reportSelfDrivingOnboardingCompleted: (productKey: string) => ({ productKey }),
        reportSelfDrivingOnboardingInstallModeSelected: (mode: 'cloud' | 'local') => ({ mode }),
        reportSelfDrivingOnboardingPlanSelected: (plan: 'free' | 'pay_as_you_go') => ({ plan }),
        // Cloud-run funnel events mirror the backend `task_run_created` / `task_run_completed`
        // lifecycle events (products/tasks/backend/models.py) and reuse their property names.
        reportSelfDrivingOnboardingCloudRunQueued: (props: { taskId: string; runId: string; repository: string }) =>
            props,
        reportSelfDrivingOnboardingCloudRunCompleted: (props: {
            taskId: string
            runId: string
            status: 'completed' | 'failed' | 'cancelled'
            durationSeconds: number | null
            prOpened: boolean
            prUrl: string | null
        }) => props,
        // Engagement with the shared wizard sync surface (FAB card / launcher / dialog), fired for
        // both variants and both run modes (GROW-121).
        reportWizardSyncExpanded: (props: { runKey: string; mode: 'cloud' | 'local'; phase: string }) => props,
        reportWizardSyncMinimized: (props: { runKey: string; mode: 'cloud' | 'local'; phase: string }) => props,
        reportWizardSyncRestored: (props: { runKey: string; mode: 'cloud' | 'local'; phase: string }) => props,
        reportWizardSyncRunDismissed: (props: {
            runKey: string
            mode: 'cloud' | 'local'
            phase: string
            elapsedSeconds: number
        }) => props,
        // The completed-handoff funnel: exposure (a run's completed state rendered anywhere) and
        // the handoff doc dialog opening. Exposure is deduped per run per pageload here, so
        // surfaces can report unconditionally. No doc content — same rule as repo names.
        reportWizardSyncHandoffShown: (props: {
            runKey: string
            mode: 'cloud' | 'local'
            surface: 'inline' | 'fab'
            prOpened: boolean
        }) => props,
        reportWizardSyncHandoffDocOpened: (props: {
            runKey: string
            mode: 'cloud' | 'local'
            trigger: 'auto' | 'button'
        }) => props,
    }),
    listeners(({ values }) => ({
        // The flow always enters at the welcome step, so `started` carries a fixed entry point
        // (legacy uses e.g. 'product_selection'). It has to match the `step_key` on the first
        // `onboarding step viewed`, or funnels segmenting on it disagree with themselves.
        reportSelfDrivingOnboardingStarted: () => {
            posthog.capture('onboarding started', {
                entry_point: 'welcome',
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        reportSelfDrivingOnboardingStepViewed: ({ stepId }) => {
            posthog.capture('onboarding step viewed', {
                step_key: stepId,
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        reportSelfDrivingOnboardingStepCompleted: ({ stepId }) => {
            posthog.capture('onboarding step completed', {
                step_key: stepId,
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        reportSelfDrivingOnboardingStepSkipped: ({ stepId }) => {
            posthog.capture('onboarding step skipped', {
                step_key: stepId,
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        reportSelfDrivingOnboardingCompleted: ({ productKey }) => {
            posthog.capture('onboarding completed', {
                product_key: productKey,
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        reportSelfDrivingOnboardingInstallModeSelected: ({ mode }) => {
            posthog.capture('onboarding install mode selected', {
                mode,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportSelfDrivingOnboardingPlanSelected: ({ plan }) => {
            posthog.capture('onboarding plan selected', {
                plan,
                ...SELF_DRIVING_ONBOARDING_EVENT_PROPS,
            })
        },
        // Deliberately NOT capturing the repository name or PR URL: they identify customers'
        // (often private) repos and this event lands in the shared app analytics project. The
        // backend task_run_* lifecycle events carry them server-side; task_id/run_id join to them.
        reportSelfDrivingOnboardingCloudRunQueued: ({ taskId, runId }) => {
            posthog.capture('onboarding cloud run queued', {
                task_id: taskId,
                run_id: runId,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportSelfDrivingOnboardingCloudRunCompleted: ({ taskId, runId, status, durationSeconds, prOpened }) => {
            posthog.capture('onboarding cloud run completed', {
                task_id: taskId,
                run_id: runId,
                status,
                duration_seconds: durationSeconds,
                pr_opened: prOpened,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportWizardSyncExpanded: ({ runKey, mode, phase }) => {
            posthog.capture('wizard sync expanded', {
                run_key: runKey,
                mode,
                phase,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportWizardSyncMinimized: ({ runKey, mode, phase }) => {
            posthog.capture('wizard sync minimized', {
                run_key: runKey,
                mode,
                phase,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportWizardSyncRestored: ({ runKey, mode, phase }) => {
            posthog.capture('wizard sync restored', {
                run_key: runKey,
                mode,
                phase,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportWizardSyncRunDismissed: ({ runKey, mode, phase, elapsedSeconds }) => {
            posthog.capture('wizard sync run dismissed', {
                run_key: runKey,
                mode,
                phase,
                elapsed_seconds: elapsedSeconds,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        reportWizardSyncHandoffShown: ({ runKey, mode, surface, prOpened }) => {
            if (reportedHandoffShownRuns.has(runKey)) {
                return
            }
            reportedHandoffShownRuns.add(runKey)
            posthog.capture('wizard sync handoff shown', {
                run_key: runKey,
                mode,
                surface,
                pr_opened: prOpened,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
        // Opens are NOT deduped: reopening the doc through the button is real engagement, and the
        // auto trigger fires at most once per run by construction (wizardSyncUiLogic's seen keys).
        reportWizardSyncHandoffDocOpened: ({ runKey, mode, trigger }) => {
            posthog.capture('wizard sync handoff doc opened', {
                run_key: runKey,
                mode,
                trigger,
                ...wizardSyncEventProps(values.featureFlags),
            })
        },
    })),
])
