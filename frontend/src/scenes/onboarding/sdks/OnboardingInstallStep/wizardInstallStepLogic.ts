export type wizardInstallStepLogicType = MakeLogicType<
    wizardInstallStepLogicValues,
    wizardInstallStepLogicActions,
    Record<string, any>,
    wizardInstallStepLogicMeta
>

export const wizardInstallStepLogic = kea<wizardInstallStepLogicType>([
    path(['scenes', 'onboarding', 'wizardInstallStepLogic']),
    connect({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            preflightLogic,
            ['preflight'],
            teamLogic,
            ['currentTeam'],
            userLogic,
            ['user'],
        ],
    }),
    actions({
        setManualModalOpen: (open: boolean) => ({ open }),
        setSdkInstructionsOpen: (open: boolean) => ({ open }),
    }),
    reducers({
        manualModalOpen: [
            false,
            {
                setManualModalOpen: (_, { open }) => open,
            },
        ],
        sdkInstructionsOpen: [
            false,
            {
                setSdkInstructionsOpen: (_, { open }) => open,
            },
        ],
    }),
    selectors({
        cloudRunEnabled: [
            (s) => [s.featureFlags, s.preflight],
            (flags: FeatureFlagsSet, preflight: PreflightStatus | null): boolean =>
                flags[FEATURE_FLAGS.WIZARD_ONBOARDING_CLOUD_RUNS_ENABLED] === true &&
                !!preflight?.wizard_cloud_run_available &&
                !!(preflight.cloud || preflight.is_debug),
        ],
        cloudRunProps: [
            (s) => [s.cloudRunEnabled, s.currentTeam, s.user],
            (
                enabled: boolean,
                team: TeamType | TeamPublicType | null,
                user: UserType | null
            ): WizardOnboardingCloudRunProps | null =>
                enabled && team && user ? { projectId: String(team.id), userId: user.id } : null,
        ],
    }),
    listeners({
        setManualModalOpen: ({ open }) => {
            if (open) {
                posthog.capture('wizard manual setup opened', { event_source: 'wizard_ui', location: 'onboarding' })
            }
        },
    }),
])
