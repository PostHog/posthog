export type onboardingRoleNotificationsLogicType = MakeLogicType<
    onboardingRoleNotificationsLogicValues,
    onboardingRoleNotificationsLogicActions,
    Record<string, any>,
    onboardingRoleNotificationsLogicMeta
>

export const onboardingRoleNotificationsLogic = kea<onboardingRoleNotificationsLogicType>([
    path(['scenes', 'onboarding', 'legacy', 'notifications', 'onboardingRoleNotificationsLogic']),
    connect(() => ({
        values: [userLogic, ['user'], projectLogic, ['currentProjectId'], featureFlagLogic, ['featureFlags']],
        actions: [eventUsageLogic, ['reportOnboardingRoleReportSubscribed', 'reportOnboardingRoleReportRemoved']],
    })),
    selectors({
        report: [
            (s) => [s.user],
            (user: UserType | null): RoleReportDefinition => reportForRole(user?.role_at_organization),
        ],
    }),
    loaders(({ actions, values }) => ({
        createdSubscriptionId: [
            null as number | null,
            {
                createRoleSubscription: async (): Promise<number | null> => {
                    if (values.createdSubscriptionId !== null || !values.currentProjectId) {
                        return values.createdSubscriptionId
                    }
                    const report = values.report
                    try {
                        const created = await subscriptionsCreate(String(values.currentProjectId), {
                            // resource_type derives to 'ai_prompt' server-side from the prompt
                            prompt: report.prompt,
                            title: report.title,
                            target_type: 'email',
                            target_value: values.user?.email ?? '',
                            frequency: 'weekly',
                            interval: 1,
                            // A week out: the user declares interest now, the first report fires
                            // once there's been time to instrument and collect data.
                            start_date: dayjs().add(7, 'day').hour(9).minute(0).second(0).toISOString(),
                            // Defaults to true on create, which would deliver an AI report over a
                            // project that likely has no events yet.
                            send_test_now: false,
                        })
                        actions.reportOnboardingRoleReportSubscribed(
                            values.user?.role_at_organization ?? null,
                            report.key,
                            resolveRoleNotificationsArm(values.featureFlags)
                        )
                        return created.id
                    } catch {
                        lemonToast.error(
                            'Could not set up the report. You can add it later from Notifications & alerts.'
                        )
                        return values.createdSubscriptionId
                    }
                },
                removeRoleSubscription: async (): Promise<number | null> => {
                    const subscriptionId = values.createdSubscriptionId
                    if (subscriptionId === null || !values.currentProjectId) {
                        return values.createdSubscriptionId
                    }
                    try {
                        // Subscriptions have no hard delete; setting `deleted` soft-deletes.
                        await subscriptionsPartialUpdate(String(values.currentProjectId), subscriptionId, {
                            deleted: true,
                        })
                        actions.reportOnboardingRoleReportRemoved(
                            values.user?.role_at_organization ?? null,
                            values.report.key,
                            resolveRoleNotificationsArm(values.featureFlags)
                        )
                        return null
                    } catch {
                        lemonToast.error('Could not undo. You can remove the report from Notifications & alerts.')
                        return values.createdSubscriptionId
                    }
                },
            },
        ],
    })),
])
