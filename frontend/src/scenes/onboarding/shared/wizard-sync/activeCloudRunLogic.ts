/**
 * Holds the active cloud-run handle app-wide so the global progress FAB can keep showing a run after
 * the user advances past (or unmounts) the install step. Persisted so it also survives a refresh during
 * a long run. The install step writes it on kickoff; the FAB clears it on dismiss.
 *
 * The persisted handle lives in localStorage, which is shared across every account and project on this
 * browser — so `activeCloudRun` only surfaces a handle stamped with the current project. Without that
 * gate a fresh account inherits the previous account's run and greets the user with a progress widget
 * for a run that isn't theirs.
 *
 * localStorage is also the only thing keeping the handle alive: nothing else expires it, so it is
 * reconciled against the server (`hydrateFromServer`). While a handle is held that happens on mount,
 * whenever the tab becomes visible, and every RECONCILE_INTERVAL_MS, whoever holds it. With no
 * handle only the mount reconcile runs, and only for the drop-flow signup on a team still in
 * onboarding, the one case a server answer can seed from.
 */
export const activeCloudRunLogic = kea<activeCloudRunLogicType>([
    path(['scenes', 'onboarding', 'activeCloudRunLogic']),
    connect(() => ({
        values: [projectLogic, ['currentProjectId'], teamLogic, ['currentTeam'], userLogic, ['isProvisionedUser']],
    })),
    actions({
        setActiveCloudRun: (taskId: string, runId: string, startedAt: string, projectId: number) => ({
            taskId,
            runId,
            startedAt,
            projectId,
        }),
        clearActiveCloudRun: true,
        // Set by the inline install-step progress view while it's mounted, so the floating FAB hides
        // and the two never render the same run at once.
        // Last-writer-wins boolean, not a refcount: at most ONE inline view may be mounted at a time,
        // or the first unmount un-hides the FAB while the second view is still on screen.
        // Reconcile the persisted handle against the server's view of the project's active wizard
        // cloud run: seeds a handle the client never wrote (drop-flow signups start the run
        // server-side) and retires one the server no longer reports.
        hydrateFromServer: true,
        // Ask the backend to cancel the active run (terminates the workflow and tears down the
        // sandbox). The handle is kept: the run stream delivers the terminal `cancelled` status,
        // so the surface shows the outcome and the user dismisses it like any finished run.
        cancelActiveCloudRun: true,
        cancelActiveCloudRunSuccess: true,
        cancelActiveCloudRunFailure: true,
    }),
    reducers({
        persistedCloudRun: [
            null as CloudRunHandle | null,
            { persist: true },
            {
                setActiveCloudRun: (_, { taskId, runId, startedAt, projectId }) => ({
                    taskId,
                    runId,
                    startedAt,
                    projectId,
                }),
                clearActiveCloudRun: () => null,
            },
        ],
        // Guards the Cancel button against double-submission while the request is in flight.
        // It resets on success too: the terminal status normally arrives via the stream and
        // removes the button, but if the stream disconnects first, a permanently disabled
        // button would strand the user — a repeat cancel is idempotent server-side. A new
        // handle also resets it, since the flag belongs to the run it was set for.
        cancellingRun: [
            false,
            {
                cancelActiveCloudRun: () => true,
                cancelActiveCloudRunSuccess: () => false,
                cancelActiveCloudRunFailure: () => false,
                clearActiveCloudRun: () => false,
                setActiveCloudRun: () => false,
            },
        ],
    }),
    selectors({
        activeCloudRun: [
            (s) => [s.persistedCloudRun, s.currentProjectId],
            (persistedCloudRun: CloudRunHandle | null, currentProjectId: number | null): CloudRunHandle | null =>
                scopedCloudRun(persistedCloudRun, currentProjectId),
        ],
        // Whether a reconcile is worth a request, checked as inputs load rather than once on mount,
        // so a run whose project resolved late still gets reconciled. This logic is mounted app-wide
        // (the FAB lives in the authenticated shell), so the gate keeps the unconditional pageload
        // request off the accounts it can do nothing for. A held handle always needs checking,
        // whoever holds it. With no handle the only thing a request can do is seed one, which is
        // only ever offered to the drop-flow signup on a team still in onboarding (see
        // reconcileCloudRun for why adoption is not open to everyone), so nobody else spends one.
        canHydrateFromServer: [
            (s) => [s.currentProjectId, s.currentTeam, s.activeCloudRun, s.isProvisionedUser],
            (
                currentProjectId: number | null,
                currentTeam: TeamType | null,
                activeCloudRun: CloudRunHandle | null,
                isProvisionedUser: boolean
            ): boolean =>
                currentProjectId != null &&
                currentTeam != null &&
                (activeCloudRun !== null || (isProvisionedUser && !currentTeam.completed_snippet_onboarding)),
        ],
    }),
    listeners(({ actions, values }) => ({
        cancelActiveCloudRun: async () => {
            const handle = values.activeCloudRun
            const projectId = values.currentProjectId
            if (!handle || projectId == null) {
                actions.cancelActiveCloudRunFailure()
                return
            }
            try {
                await tasksRunsCancelCreate(String(projectId), handle.taskId, handle.runId)
                actions.cancelActiveCloudRunSuccess()
            } catch {
                lemonToast.error('Could not cancel the run. Please try again.')
                actions.cancelActiveCloudRunFailure()
            }
        },
        hydrateFromServer: async () => {
            const projectId = values.currentProjectId
            if (projectId == null) {
                return
            }
            // The handle the answer will be about. A kickoff (or a dismiss) can land while the
            // request is in flight, and the server was never asked about that run: applying a 204
            // computed before it existed would retire a run the user just started.
            const requestedRunId = values.activeCloudRun?.runId ?? null
            try {
                const response = await tasksActiveWizardRunRetrieve(String(projectId))
                if ((values.activeCloudRun?.runId ?? null) !== requestedRunId) {
                    return
                }
                const server = (response as WizardCloudRunDTOApi | undefined) ?? null
                const decision = reconcileCloudRun(values.activeCloudRun, server, values.isProvisionedUser)
                if (decision === 'clear') {
                    actions.clearActiveCloudRun()
                } else if (decision === 'adopt' && server) {
                    actions.setActiveCloudRun(
                        server.task_id,
                        server.run_id,
                        server.started_at ?? new Date().toISOString(),
                        projectId
                    )
                }
            } catch {
                // Best-effort: a failed reconcile leaves the handle exactly as it was.
            }
        },
    })),
    subscriptions(({ actions }) => ({
        // Fires once on mount (with the current value) and again whenever readiness changes, so
        // hydration runs as soon as the project is available — not just if it happened to be ready at
        // mount. hydrateFromServer is idempotent, so a no-op false value is harmless.
        canHydrateFromServer: (canHydrate: boolean) => {
            if (canHydrate) {
                actions.hydrateFromServer()
            }
        },
    })),
    afterMount(({ actions, values, cache }) => {
        // A run can finish or be cancelled while this tab sits in the background. Opting out of the
        // disposables pause is what makes this fire at all: a paused listener is detached, so it
        // would never hear the tab come back.
        cache.disposables.add(
            () => {
                const onVisibilityChange = (): void => {
                    // Guarded like the interval below: with no handle there is nothing to retire,
                    // and a request per tab focus for every account in the app buys nothing the
                    // mount reconcile has not already covered.
                    if (!document.hidden && values.activeCloudRun) {
                        actions.hydrateFromServer()
                    }
                }
                document.addEventListener('visibilitychange', onVisibilityChange)
                return () => document.removeEventListener('visibilitychange', onVisibilityChange)
            },
            'reconcile-on-visible',
            { pauseOnPageHidden: false }
        )
        // Only while a handle is held: with none there is nothing to retire, and a server-side run
        // reaches the FAB through the mount reconcile anyway. The interval keeps the disposables
        // pause, so a background tab does not poll.
        cache.disposables.add(() => {
            const timer = window.setInterval(() => {
                if (values.activeCloudRun) {
                    actions.hydrateFromServer()
                }
            }, RECONCILE_INTERVAL_MS)
            return () => window.clearInterval(timer)
        }, 'reconcile-interval')
    }),
])
