import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { projectLogic } from 'scenes/projectLogic'

import type { WizardSessionDTOApi } from 'products/wizard/frontend/generated/api.schemas'

import { startedByFromSession } from './helpers'
import { wizardSyncUiLogic } from './wizardSyncUiLogic'

/** A terminal local wizard run, snapshotted so its handoff outlives the session stream. */
export interface FinishedLocalRunHandle {
    sessionId: string
    /** Project the run belongs to — the handle lives in localStorage, shared across accounts. */
    projectId: number
    startedAt: string
    finishedAt: string
    runPhase: 'completed' | 'error'
    tasks: { id: string; title: string; status: string }[]
    error: { message?: string } | null
    startedBy?: { name: string; email: string } | null
    /** The run's markdown handoff doc, kept so the doc dialog outlives the stream too. */
    handoffText?: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface finishedLocalRunLogicValues {
    currentProjectId: number | null // projectLogic
    dismissedSessionId: string | null
    finishedLocalRun: FinishedLocalRunHandle | null
    persistedFinishedLocalRun: FinishedLocalRunHandle | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface finishedLocalRunLogicActions {
    handoffDocReceived: (doc: { key: string; startedByEmail: string | null; text: string }) => {
        key: string
        startedByEmail: string | null
        text: string
    } // wizardSyncUiLogic
    dismissLocalRun: (sessionId: string) => {
        sessionId: string
    }
    recordFinishedLocalRun: (session: WizardSessionDTOApi) => {
        session: WizardSessionDTOApi
    }
    setFinishedLocalRun: (handle: FinishedLocalRunHandle) => {
        handle: FinishedLocalRunHandle
    }
    supersedeFinishedLocalRun: (sessionId: string) => {
        sessionId: string
    }
}

