import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { lemonToast } from '@posthog/lemon-ui'

import { addProductIntent } from 'lib/utils/product-intents'
import { teamLogic } from 'scenes/teamLogic'

import { productEnablementCreate } from '~/generated/core/api'
import { ProductIntentContext, ProductKey } from '~/queries/schema/schema-general'
import type { TeamType } from '~/types'

import type { TeamPublicType } from '../../../types'

/** The tools the onboarding can turn on, keyed by the product_enablement API's product names. */
export type EnablementProduct = 'session_replay' | 'error_tracking'

const PRODUCT_KEY: Record<EnablementProduct, ProductKey> = {
    session_replay: ProductKey.SESSION_REPLAY,
    error_tracking: ProductKey.ERROR_TRACKING,
}

// Mirrors the legacy flow's primary/secondary intent split so activation funnels stay comparable
// across variants: product analytics is the always-on primary, the opt-in tools are secondary.
const INTENT_METADATA = { flow_variant: 'context_first' }

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface productEnablementStepLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    enablingProduct: EnablementProduct | null
    isErrorTrackingEnabled: boolean
    isSessionReplayEnabled: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface productEnablementStepLogicActions {
    loadCurrentTeam: () => any // teamLogic
    enableProduct: (
        product: EnablementProduct,
        onSuccess?: () => void
    ) => {
        onSuccess: (() => void) | undefined
        product: EnablementProduct
    }
    enableProductFailure: (product: EnablementProduct) => {
        product: EnablementProduct
    }
    enableProductSuccess: (product: EnablementProduct) => {
        product: EnablementProduct
    }
    registerAnalyticsIntent: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface productEnablementStepLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        isSessionReplayEnabled: (currentTeam: TeamPublicType | TeamType | null) => boolean
        isErrorTrackingEnabled: (currentTeam: TeamPublicType | TeamType | null) => boolean
    }
}

export type productEnablementStepLogicType = MakeLogicType<
    productEnablementStepLogicValues,
    productEnablementStepLogicActions,
    Record<string, any>,
    productEnablementStepLogicMeta
>

/**
 * Enables tools during the self-driving onboarding via the product_enablement endpoint (server-owned
 * recipes: the primary opt-in plus conservative companion defaults). One product per call so a
 * failure on an admin-gated toggle can't take down the others, and registers the matching product
 * intent so activation reporting matches the legacy flow.
 */
export const productEnablementStepLogic = kea<productEnablementStepLogicType>([
    path(['scenes', 'onboarding', 'self-driving', 'productEnablementStepLogic']),

    connect(() => ({
        values: [teamLogic, ['currentTeam']],
        actions: [teamLogic, ['loadCurrentTeam']],
    })),

    actions({
        enableProduct: (product: EnablementProduct, onSuccess?: () => void) => ({ product, onSuccess }),
        enableProductSuccess: (product: EnablementProduct) => ({ product }),
        enableProductFailure: (product: EnablementProduct) => ({ product }),
        registerAnalyticsIntent: true,
    }),

    reducers({
        enablingProduct: [
            null as EnablementProduct | null,
            {
                enableProduct: (_, { product }) => product,
                enableProductSuccess: () => null,
                enableProductFailure: () => null,
            },
        ],
    }),

    selectors({
        isSessionReplayEnabled: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | null): boolean => !!currentTeam?.session_recording_opt_in,
        ],
        isErrorTrackingEnabled: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | null): boolean => !!currentTeam?.autocapture_exceptions_opt_in,
        ],
    }),

    listeners(({ actions, cache }) => ({
        enableProduct: async ({ product, onSuccess }) => {
            try {
                await productEnablementCreate(String(teamLogic.values.currentTeamId), { products: [product] })
            } catch (error: any) {
                actions.enableProductFailure(product)
                lemonToast.error(error?.detail || error?.message || "Couldn't turn this on. Please try again.")
                return // stay on the step so the user can retry or skip
            }
            actions.enableProductSuccess(product)
            // Refresh the cached team so the opt-in toggles read back as on everywhere.
            actions.loadCurrentTeam()
            void addProductIntent({
                product_type: PRODUCT_KEY[product],
                intent_context: ProductIntentContext.ONBOARDING_PRODUCT_SELECTED_SECONDARY,
                metadata: INTENT_METADATA,
            })
            onSuccess?.()
        },
        registerAnalyticsIntent: () => {
            // The step remounts freely (back navigation, refresh) - register once per pageload.
            if (cache.analyticsIntentRegistered) {
                return
            }
            cache.analyticsIntentRegistered = true
            void addProductIntent({
                product_type: ProductKey.PRODUCT_ANALYTICS,
                intent_context: ProductIntentContext.ONBOARDING_PRODUCT_SELECTED_PRIMARY,
                metadata: INTENT_METADATA,
            })
        },
    })),
])
