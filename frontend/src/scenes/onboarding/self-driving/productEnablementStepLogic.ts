/**
 * Applies the selected use case's setup: turns on the tools' toggleable options via the
 * product_enablement endpoint and registers the setup's product intents, which is what populates
 * the sidebar. One product per enablement call so a failure on an admin-gated toggle can't take
 * down the others.
 */
export const productEnablementStepLogic = kea<productEnablementStepLogicType>([
    path(['scenes', 'onboarding', 'self-driving', 'productEnablementStepLogic']),

    connect(() => ({
        values: [teamLogic, ['currentTeam'], useCaseSelectionLogic, ['selectedUseCase']],
        actions: [teamLogic, ['loadCurrentTeam']],
    })),

    actions({
        enableProduct: (product: EnablementProduct, onSuccess?: () => void) => ({ product, onSuccess }),
        enableProductSuccess: (product: EnablementProduct) => ({ product }),
        enableProductFailure: (product: EnablementProduct) => ({ product }),
        configureUseCase: (useCase: OnboardingUseCaseKey | null) => ({ useCase }),
        configureUseCaseFinished: true,
    }),

    reducers({
        enablingProduct: [
            null as EnablementProduct | null,
            {
                enableProduct: (_, { product }) => product,
                enableProductSuccess: () => null,
                enableProductFailure: () => null,
            },
        ],
        // The tools screen shows up while the auto-enable calls are still in flight - this keeps
        // its rows in a loading state instead of flashing "Turn on".
        autoEnabling: [
            false,
            {
                configureUseCase: () => true,
                configureUseCaseFinished: () => false,
            },
        ],
    }),

    selectors({
        isSessionReplayEnabled: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | null): boolean => !!currentTeam?.session_recording_opt_in,
        ],
        isErrorTrackingEnabled: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | null): boolean => !!currentTeam?.autocapture_exceptions_opt_in,
        ],
    }),

    listeners(({ actions, values }) => ({
        enableProduct: async ({ product, onSuccess }) => {
            try {
                await productEnablementCreate(String(teamLogic.values.currentTeamId), { products: [product] })
            } catch (error: any) {
                actions.enableProductFailure(product)
                lemonToast.error(error?.detail || error?.message || "Couldn't turn this on. Please try again.")
                return // stay on the step so the user can retry or skip
            }
            actions.enableProductSuccess(product)
            // Refresh the cached team so the opt-in toggles read back as on everywhere.
            actions.loadCurrentTeam()
            onSuccess?.()
        },
        configureUseCase: async ({ useCase }) => {
            const setup = resolveSetup(useCase)

            // Turn on the toggleable tools without asking - the tools screen reads the result back
            // as "Enabled" and keeps a "Turn on" button as the fallback for any call that failed
            // here (which is why failures are silent: the user never asked for this call).
            const toggles = setup.tools
                .map((key) => toolEnablement(ONBOARDING_TOOLS[key]))
                .filter((product): product is EnablementProduct => !!product)
            let enabledAny = false
            for (const product of toggles) {
                const alreadyOn =
                    product === 'session_replay' ? values.isSessionReplayEnabled : values.isErrorTrackingEnabled
                if (alreadyOn) {
                    continue
                }
                try {
                    await productEnablementCreate(String(teamLogic.values.currentTeamId), { products: [product] })
                } catch {
                    continue
                }
                enabledAny = true
            }
            if (enabledAny) {
                actions.loadCurrentTeam()
            }

            // Register the whole setup's intents - tools and sidebar extras alike - so the sidebar
            // gets populated (UserProductList resolves them through the products registry). The
            // primary was already registered at use-case selection; with no use case, the default
            // setup's primary takes that slot here.
            const primary = setup.primaryProduct
            const productKeys = new Set<ProductKey>([
                ...setup.tools.map((key) => ONBOARDING_TOOLS[key].productKey),
                ...setup.sidebarExtras,
            ])
            if (!useCase) {
                void addProductIntent({
                    product_type: primary,
                    intent_context: ProductIntentContext.ONBOARDING_PRODUCT_SELECTED_PRIMARY,
                    metadata: SELF_DRIVING_INTENT_METADATA,
                })
            }
            for (const productKey of productKeys) {
                if (productKey === primary) {
                    continue
                }
                void addProductIntent({
                    product_type: productKey,
                    intent_context: ProductIntentContext.ONBOARDING_PRODUCT_SELECTED_SECONDARY,
                    metadata: SELF_DRIVING_INTENT_METADATA,
                })
            }

            actions.configureUseCaseFinished()
        },
    })),
])
