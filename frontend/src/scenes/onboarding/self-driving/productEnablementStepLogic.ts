import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { lemonToast } from '@posthog/lemon-ui'

import { addProductIntent } from 'lib/utils/product-intents'
import { teamLogic } from 'scenes/teamLogic'

import { productEnablementCreate } from '~/generated/core/api'
import { ProductIntentContext, ProductKey } from '~/queries/schema/schema-general'
import type { TeamType } from '~/types'

import type { TeamPublicType } from '../../../types'
import { GOAL_PRIMARY_PRODUCT, SELF_DRIVING_INTENT_METADATA } from './goals'
import type { SelfDrivingGoal } from './goals'
import { goalSelectionLogic } from './goalSelectionLogic'

/** The tools the onboarding can turn on, keyed by the product_enablement API's product names. */
export type EnablementProduct = 'session_replay' | 'error_tracking'

const PRODUCT_KEY: Record<EnablementProduct, ProductKey> = {
    session_replay: ProductKey.SESSION_REPLAY,
    error_tracking: ProductKey.ERROR_TRACKING,
}

/** What each goal turns on automatically - only tools with a team toggle; the goals whose steps are
 * instrumentation (authorized URLs, AI SDK setup) have nothing to flip here. */
const GOAL_AUTO_ENABLED: Record<SelfDrivingGoal, EnablementProduct[]> = {
    user_behavior: ['session_replay'],
    fix_issues: ['error_tracking', 'session_replay'],
    website_traffic: [],
    ai_app: [],
}

const ALL_ENABLEMENT_PRODUCTS: EnablementProduct[] = ['session_replay', 'error_tracking']

/** The goal's own product was already registered as primary at goal selection - everything else
 * enabled along the way is secondary. */
function registerEnablementIntent(product: EnablementProduct, goal: SelfDrivingGoal | null): void {
    if (!goal || GOAL_PRIMARY_PRODUCT[goal] !== PRODUCT_KEY[product]) {
        void addProductIntent({
            product_type: PRODUCT_KEY[product],
            intent_context: ProductIntentContext.ONBOARDING_PRODUCT_SELECTED_SECONDARY,
            metadata: SELF_DRIVING_INTENT_METADATA,
        })
    }
}

