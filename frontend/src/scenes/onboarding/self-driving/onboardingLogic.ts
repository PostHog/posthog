import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { router } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import { eventUsageLogic, type OnboardingEventProperties } from 'lib/utils/eventUsageLogic'
import { completeProductOnboarding, teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { customProductsLogic } from '~/layout/panel-layout/ProjectTree/customProductsLogic'
import { ProductIntentContext, ProductKey } from '~/queries/schema/schema-general'
import type { TeamPublicType, TeamType } from '~/types'

import { SELF_DRIVING_ONBOARDING_EVENT_PROPS } from '../onboardingEventUsageLogic'
import { optionsForSetup, productKeysForSetup, resolveSetup } from '../shared/useCases'
import type { TeamOption } from '../shared/useCases'
import type { OnboardingUseCaseKey } from '../shared/useCases'
import { useCaseSelectionLogic } from './useCaseSelectionLogic'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface onboardingLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    isCompleting: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface onboardingLogicActions {
    loadCustomProducts: () => any // customProductsLogic
    reportOnboardingCompleted: (
        productKey: string,
        properties?: OnboardingEventProperties | undefined
    ) => {
        productKey: string
        properties: OnboardingEventProperties | undefined
    } // eventUsageLogic
    updateCurrentTeam: (payload: Partial<TeamType>) => Partial<TeamType> // teamLogic
    clearUseCase: () => {
        value: true
    } // useCaseSelectionLogic
    completeOnboarding: (useCase?: OnboardingUseCaseKey | null) => {
        useCase: OnboardingUseCaseKey | null
    }
    setIsCompleting: (isCompleting: boolean) => {
        isCompleting: boolean
    }
}

export type onboardingLogicType = MakeLogicType<onboardingLogicValues, onboardingLogicActions>

function completedOnboardingMap(
    team: TeamPublicType | TeamType | null,
    products: ProductKey[]
): Record<string, boolean> {
    const completedMap: Record<string, boolean> = { ...team?.has_completed_onboarding_for }
    for (const productKey of products) {
        completedMap[productKey] = true
    }
    return completedMap
}

function optionsPayload(team: TeamPublicType | TeamType | null, options: TeamOption[]): Partial<TeamType> {
    return {
        ...(options.includes('session_recording') ? { session_recording_opt_in: true } : {}),
        ...(options.includes('replay_masking_floor') && team?.session_recording_masking_config == null
            ? { session_recording_masking_config: { maskAllInputs: true } }
            : {}),
        ...(options.includes('exception_autocapture') ? { autocapture_exceptions_opt_in: true } : {}),
        ...(options.includes('web_vitals') ? { autocapture_web_vitals_opt_in: true } : {}),
        ...(options.includes('console_log_capture') ? { capture_console_log_opt_in: true } : {}),
        ...(options.includes('network_performance') ? { capture_performance_opt_in: true } : {}),
        ...(options.includes('heatmaps') ? { heatmaps_opt_in: true } : {}),
        ...(options.includes('dead_clicks') ? { capture_dead_clicks: true } : {}),
    }
}

export const onboardingLogic = kea<onboardingLogicType>([
    path(['scenes', 'onboarding', 'self-driving', 'onboardingLogic']),

    connect(() => ({
        values: [teamLogic, ['currentTeam']],
        actions: [
            teamLogic,
            ['updateCurrentTeam'],
            customProductsLogic,
            ['loadCustomProducts'],
            useCaseSelectionLogic,
            ['clearUseCase'],
            eventUsageLogic,
            ['reportOnboardingCompleted'],
        ],
    })),

    actions({
        completeOnboarding: (useCase?: OnboardingUseCaseKey | null) => ({ useCase: useCase ?? null }),
        setIsCompleting: (isCompleting: boolean) => ({ isCompleting }),
    }),

    reducers({
        isCompleting: [
            false,
            {
                setIsCompleting: (_, { isCompleting }) => isCompleting,
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        completeOnboarding: async ({ useCase }) => {
            if (values.isCompleting) {
                return
            }
            actions.setIsCompleting(true)
            const team = values.currentTeam
            const setup = resolveSetup(useCase)
            const products = productKeysForSetup(setup)
            const options = optionsForSetup(setup)
            const needsReplayAdminSetup =
                options.includes('replay_masking_floor') && team?.session_recording_masking_config == null
            try {
                if (!team) {
                    throw new Error('Current team is not loaded')
                }
                const {
                    session_recording_opt_in,
                    session_recording_masking_config,
                    capture_console_log_opt_in,
                    capture_performance_opt_in,
                    heatmaps_opt_in,
                    capture_dead_clicks,
                    ...otherOptions
                } = optionsPayload(team, options)
                const memberOptions = needsReplayAdminSetup
                    ? otherOptions
                    : {
                          ...otherOptions,
                          ...(session_recording_opt_in ? { session_recording_opt_in } : {}),
                      }
                if (Object.keys(memberOptions).length > 0) {
                    await teamLogic.asyncActions.updateCurrentTeam(memberOptions)
                }
                const adminOptions = needsReplayAdminSetup
                    ? {
                          ...(session_recording_opt_in ? { session_recording_opt_in } : {}),
                          session_recording_masking_config,
                          capture_console_log_opt_in,
                          capture_performance_opt_in,
                          heatmaps_opt_in,
                          capture_dead_clicks,
                      }
                    : {
                          session_recording_masking_config,
                          capture_console_log_opt_in,
                          capture_performance_opt_in,
                          heatmaps_opt_in,
                          capture_dead_clicks,
                      }
                if (Object.values(adminOptions).some(Boolean)) {
                    try {
                        await teamLogic.asyncActions.updateCurrentTeam(adminOptions)
                    } catch {
                        lemonToast.warning('Some settings could not be enabled. An admin can finish them later.')
                    }
                }
                await Promise.all(
                    products.map((productKey) =>
                        completeProductOnboarding(team.id, {
                            product_type: productKey,
                            intent_context:
                                productKey === setup.primaryProduct
                                    ? ProductIntentContext.ONBOARDING_PRODUCT_SELECTED_PRIMARY
                                    : ProductIntentContext.ONBOARDING_PRODUCT_SELECTED_SECONDARY,
                        })
                    )
                )
                actions.loadCustomProducts()
                await teamLogic.asyncActions.updateCurrentTeam({
                    completed_snippet_onboarding: true,
                    has_completed_onboarding_for: completedOnboardingMap(team, products),
                })
                actions.clearUseCase()
                actions.reportOnboardingCompleted(setup.primaryProduct, SELF_DRIVING_ONBOARDING_EVENT_PROPS)
                router.actions.push(urls.inbox())
            } catch {
                lemonToast.error("Couldn't finish onboarding. Please try again.")
            } finally {
                actions.setIsCompleting(false)
            }
        },
    })),
])
