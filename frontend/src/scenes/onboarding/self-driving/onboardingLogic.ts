import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { router } from 'kea-router'

import { lemonToast } from '@posthog/lemon-ui'

import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { productEnablementCreate } from '~/generated/core/api'
import { ProductKey } from '~/queries/schema/schema-general'
import type { TeamPublicType, TeamType } from '~/types'

import { onboardingEventUsageLogic } from '../onboardingEventUsageLogic'
import { ONBOARDING_TOOLS, resolveSetup, toolEnablement } from '../shared/useCases'
import type { EnablementProduct } from '../shared/useCases'
import type { OnboardingUseCaseKey } from '../shared/useCases'
import { useCaseSelectionLogic } from './useCaseSelectionLogic'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface onboardingLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    extraTools: ProductKey[] // useCaseSelectionLogic
    isCompleting: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface onboardingLogicActions {
    reportSelfDrivingOnboardingCompleted: (productKey: string) => {
        productKey: string
    } // onboardingEventUsageLogic
    recordProductIntentOnboardingComplete: (args_0: { product_type: ProductKey }) => {
        product_type: ProductKey
    } // teamLogic
    updateCurrentTeam: (payload: Partial<TeamType>) => Partial<TeamType> // teamLogic
    completeOnboarding: (useCase?: OnboardingUseCaseKey | null) => {
        useCase: OnboardingUseCaseKey | null
    }
    setIsCompleting: (isCompleting: boolean) => {
        isCompleting: boolean
    }
}

export type onboardingLogicType = MakeLogicType<onboardingLogicValues, onboardingLogicActions>

function creditedProductKeys(
    team: TeamPublicType | TeamType | null,
    useCase: OnboardingUseCaseKey | null,
    extraTools: ProductKey[]
): ProductKey[] {
    const products: ProductKey[] = [ProductKey.PRODUCT_ANALYTICS]
    if (team?.session_recording_opt_in) {
        products.push(ProductKey.SESSION_REPLAY)
    }
    if (team?.autocapture_exceptions_opt_in) {
        products.push(ProductKey.ERROR_TRACKING)
    }
    if (team?.surveys_opt_in) {
        products.push(ProductKey.SURVEYS)
    }
    for (const key of resolveSetup(useCase).tools) {
        const tool = ONBOARDING_TOOLS[key]
        if (!toolEnablement(tool) && !products.includes(tool.productKey)) {
            products.push(tool.productKey)
        }
    }
    for (const productKey of resolveSetup(useCase).additionalTools ?? []) {
        if (!products.includes(productKey)) {
            products.push(productKey)
        }
    }
    for (const productKey of extraTools) {
        if (!products.includes(productKey)) {
            products.push(productKey)
        }
    }
    return products
}

function completedOnboardingMap(
    team: TeamPublicType | TeamType | null,
    products: ProductKey[]
): Record<string, boolean> {
    const completedMap: Record<string, boolean> = { ...team?.has_completed_onboarding_for }
    for (const productKey of products) {
        completedMap[productKey] = true
    }
    return completedMap
}

function enablementProducts(productKeys: ProductKey[]): EnablementProduct[] {
    return Array.from(
        new Set(
            productKeys
                .map((productKey) => Object.values(ONBOARDING_TOOLS).find((tool) => tool.productKey === productKey))
                .map((tool) => (tool ? toolEnablement(tool) : undefined))
                .filter((product): product is EnablementProduct => !!product)
        )
    )
}

export const onboardingLogic = kea<onboardingLogicType>([
    path(['scenes', 'onboarding', 'self-driving', 'onboardingLogic']),

    connect(() => ({
        values: [teamLogic, ['currentTeam'], useCaseSelectionLogic, ['extraTools']],
        actions: [
            teamLogic,
            ['updateCurrentTeam', 'recordProductIntentOnboardingComplete'],
            onboardingEventUsageLogic,
            ['reportSelfDrivingOnboardingCompleted'],
        ],
    })),

    actions({
        completeOnboarding: (useCase?: OnboardingUseCaseKey | null) => ({ useCase: useCase ?? null }),
        setIsCompleting: (isCompleting: boolean) => ({ isCompleting }),
    }),

    reducers({
        isCompleting: [
            false,
            {
                setIsCompleting: (_, { isCompleting }) => isCompleting,
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        completeOnboarding: async ({ useCase }) => {
            if (values.isCompleting) {
                return
            }
            actions.setIsCompleting(true)
            const team = values.currentTeam
            const products = creditedProductKeys(team, useCase, values.extraTools)
            for (const productKey of products) {
                actions.reportSelfDrivingOnboardingCompleted(productKey)
                actions.recordProductIntentOnboardingComplete({ product_type: productKey })
            }
            try {
                for (const product of enablementProducts(products)) {
                    await productEnablementCreate(String(teamLogic.values.currentTeamId), { products: [product] })
                }
                await teamLogic.asyncActions.updateCurrentTeam({
                    completed_snippet_onboarding: true,
                    has_completed_onboarding_for: completedOnboardingMap(team, products),
                })
                router.actions.push(urls.inbox())
            } catch {
                lemonToast.error("Couldn't finish onboarding. Please try again.")
            } finally {
                actions.setIsCompleting(false)
            }
        },
    })),
])
