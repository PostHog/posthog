import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { LemonSelectOptions } from '@posthog/lemon-ui'

import { OrganizationMembershipLevel } from 'lib/constants'
import { teamLogic } from 'scenes/teamLogic'

import { TeamPublicType, TeamType } from '~/types'

/** Mirrors `TEAM_CONFIG_MEMBER_FIELDS` in posthog/api/team/team_config.py. The API rejects the whole
 * PATCH when a non-admin sends any other team field, so non-admins only send these. */
const TEAM_MEMBER_EDITABLE_FIELDS = new Set<string>([
    'completed_snippet_onboarding',
    'has_completed_onboarding_for',
    'onboarding_tasks',
    'session_recording_opt_in',
    'autocapture_exceptions_opt_in',
    'autocapture_web_vitals_opt_in',
    'autocapture_web_vitals_allowed_metrics',
    'surveys_opt_in',
    'primary_dashboard',
    'home_tab_dashboard',
])

export const isAdminOnlyTeamField = (field: string): boolean => !TEAM_MEMBER_EDITABLE_FIELDS.has(field)

export interface ProductConfigOptionBase {
    title: string
    description: string
    teamProperty: keyof TeamType
    visible: boolean
}

export interface ProductConfigurationToggle extends ProductConfigOptionBase {
    type: 'toggle'
    /** Sets the initial value. Use a team setting to reflect current state, or a static value to set a default. */
    value: boolean
    /** If true, the value is inverted when saving, used for 'opt_out' type settings */
    inverseToggle?: boolean
}

export interface ProductConfigurationSelect extends ProductConfigOptionBase {
    type: 'select'
    /** Sets the initial value. Use a team setting to reflect current state, or a static value to set a default. */
    value: string | number | null
    selectOptions: LemonSelectOptions<any>
    onChange?: (value: string | number | null) => Partial<TeamType>
}

export type ProductConfigOption = ProductConfigurationToggle | ProductConfigurationSelect

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface onboardingProductConfigurationLogicValues {
    configOptions: any[]
    currentTeam: TeamType | TeamPublicType | null
    isProjectAdmin: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface onboardingProductConfigurationLogicActions {
    updateCurrentTeam: (payload: Partial<TeamType>) => Partial<TeamType> // teamLogic
    saveConfiguration: () => {
        value: true
    }
    setConfigOptions: (configOptions: ProductConfigOption[]) => {
        configOptions: ProductConfigOption[]
    }
}

export type onboardingProductConfigurationLogicType = MakeLogicType<
    onboardingProductConfigurationLogicValues,
    onboardingProductConfigurationLogicActions
>

export const onboardingProductConfigurationLogic = kea<onboardingProductConfigurationLogicType>([
    path(() => ['scenes', 'onboarding', 'onboardingProductConfigurationLogic']),
    connect(() => ({
        actions: [teamLogic, ['updateCurrentTeam']],
        values: [teamLogic, ['currentTeam']],
    })),
    actions({
        setConfigOptions: (configOptions: ProductConfigOption[]) => ({ configOptions }),
        saveConfiguration: true,
    }),
    reducers(() => ({
        configOptions: [
            [],
            {
                setConfigOptions: (_, { configOptions }) => configOptions,
            },
        ],
    })),
    selectors({
        isProjectAdmin: [
            (s) => [s.currentTeam],
            (currentTeam: TeamType | TeamPublicType | null): boolean =>
                (!!currentTeam?.effective_membership_level &&
                    currentTeam.effective_membership_level >= OrganizationMembershipLevel.Admin) ||
                currentTeam?.user_access_level === 'admin',
        ],
    }),
    listeners(({ values, actions }) => ({
        saveConfiguration: async () => {
            const updateConfig: Record<string, any> = {}

            values.configOptions.forEach((configOption) => {
                if (configOption.onChange) {
                    const changes = configOption.onChange(configOption.value)
                    Object.assign(updateConfig, changes)
                } else {
                    const value = configOption.inverseToggle ? !configOption.value : configOption.value

                    updateConfig[configOption.teamProperty] = value
                }
            })

            if (!values.isProjectAdmin) {
                for (const field of Object.keys(updateConfig)) {
                    if (isAdminOnlyTeamField(field)) {
                        delete updateConfig[field]
                    }
                }
            }

            actions.updateCurrentTeam(updateConfig as Partial<TeamType>)
        },
    })),
])
