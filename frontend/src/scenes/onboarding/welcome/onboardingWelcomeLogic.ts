import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { actionToUrl, urlToAction } from 'kea-router'
import posthog from 'posthog-js'

import { availableOnboardingProducts } from 'scenes/onboarding/shared/utils'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { ProductKey } from '~/queries/schema/schema-general'
import type { OnboardingProduct, TeamPublicType, TeamType } from '~/types'

import { onboardingLogic } from '../onboardingLogic'
import { onboardingProviderRegistry } from '../stepProviderRegistry'

export interface WelcomeProduct {
    key: ProductKey
    product: OnboardingProduct
    completed: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface onboardingWelcomeLogicValues {
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    products: WelcomeProduct[]
    selectedProductKey: ProductKey | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface onboardingWelcomeLogicActions {
    startEmbeddedFlow: (productKey: ProductKey) => {
        productKey: ProductKey
    } // onboardingLogic
    selectProduct: (
        productKey: ProductKey,
        fromUrl?: boolean
    ) => {
        fromUrl: boolean
        productKey: ProductKey
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface onboardingWelcomeLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        products: (currentTeam: TeamPublicType | TeamType | null) => WelcomeProduct[]
    }
}

export type onboardingWelcomeLogicType = MakeLogicType<
    onboardingWelcomeLogicValues,
    onboardingWelcomeLogicActions,
    Record<string, any>,
    onboardingWelcomeLogicMeta
>

const isWelcomeProductKey = (key: unknown): key is ProductKey =>
    typeof key === 'string' && Object.hasOwn(availableOnboardingProducts, key) && key in onboardingProviderRegistry

export const onboardingWelcomeLogic = kea<onboardingWelcomeLogicType>([
    path(['scenes', 'onboarding', 'welcome', 'onboardingWelcomeLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam']],
        actions: [onboardingLogic, ['startEmbeddedFlow']],
    })),
    actions({
        selectProduct: (productKey: ProductKey, fromUrl: boolean = false) => ({ productKey, fromUrl }),
    }),
    reducers({
        selectedProductKey: [
            null as ProductKey | null,
            {
                selectProduct: (_, { productKey }) => productKey,
            },
        ],
    }),
    selectors({
        products: [
            (s) => [s.currentTeam],
            (currentTeam: TeamPublicType | TeamType | null): WelcomeProduct[] =>
                Object.entries(availableOnboardingProducts)
                    .filter(([key]) => isWelcomeProductKey(key))
                    .map(([key, product]) => ({
                        key: key as ProductKey,
                        product,
                        completed: !!currentTeam?.has_completed_onboarding_for?.[key],
                    })),
        ],
    }),
    listeners(({ actions }) => ({
        selectProduct: ({ productKey, fromUrl }) => {
            actions.startEmbeddedFlow(productKey)
            if (fromUrl) {
                return
            }
            // pinned: analytics event name and properties, dashboards read them
            posthog.capture('onboarding welcome product selected', { product_key: productKey })
        },
    })),
    actionToUrl(() => ({
        selectProduct: ({ productKey }) => [
            urls.onboardingWelcome(),
            { product: productKey },
            undefined,
            { replace: true },
        ],
    })),
    urlToAction(({ actions, values }) => ({
        [urls.onboardingWelcome()]: (_, { product }) => {
            // Product analytics is the plain SDK install, so the page opens on the Wizard install step.
            const productKey = isWelcomeProductKey(product) ? product : ProductKey.PRODUCT_ANALYTICS
            if (productKey !== values.selectedProductKey) {
                actions.selectProduct(productKey, true)
            }
        },
    })),
])
