function captureBlockedApplicationIfGateShown(values: startupProgramLogicValues, cache: Record<string, any>): void {
    if (!values.shouldShowEmailDomainBlockedGate || cache.blockedApplicationCaptured) {
        return
    }

    cache.blockedApplicationCaptured = true
    posthog.capture('startup program application blocked', {
        email_domain: values.userEmailDomain,
        program: values.isYC ? StartupProgramType.YC : StartupProgramType.Startup,
        organization_id: values.currentOrganizationId,
        blocked_at: 'form',
    })
}

export const startupProgramLogic = kea<startupProgramLogicType>([
    path(['scenes', 'startups', 'startupProgramLogic']),
    props({} as StartupProgramLogicProps),
    connect(() => ({
        values: [
            userLogic,
            ['user'],
            organizationLogic,
            ['currentOrganization', 'currentOrganizationId', 'isAdminOrOwner'],
            billingLogic,
            ['billing', 'isAnnualPlanCustomer'],
        ],
    })),
    actions({
        setFormSubmitted: (submitted: boolean) => ({ submitted }),
    }),
    reducers({
        formSubmitted: [
            false,
            {
                setFormSubmitted: (_, { submitted }) => submitted,
            },
        ],
    }),
    selectors({
        isYC: [() => [(_, props) => props.referrer], (referrer: string | undefined) => referrer === 'yc'],
        isReferralProgram: [
            () => [(_, props) => props.referrer],
            (referrer: string | undefined) => !!referrer && referrer !== 'yc',
        ],
        referrer: [() => [(_, props) => props.referrer], (referrer: string | undefined) => referrer],
        referrerDisplayName: [
            () => [(_, props) => props.referrer],
            (referrer: string | undefined) => {
                if (!referrer || referrer === 'yc') {
                    return undefined
                }
                return referrer.split('-').join(' ')
            },
        ],
        isCurrentlyOnStartupPlan: [
            (s) => [s.billing],
            (billing: BillingType | null) => {
                return !!billing?.startup_program_label
            },
        ],
        currentStartupProgramLabel: [
            (s) => [s.billing],
            (billing: BillingType | null) => {
                return billing?.startup_program_label || null
            },
        ],
        wasPreviouslyOnStartupPlan: [
            (s) => [s.billing],
            (billing: BillingType | null) => {
                return !!billing?.startup_program_label_previous
            },
        ],
        userEmailDomain: [(s) => [s.user], (user: UserType | null) => getEmailDomain(user?.email)],
        isEmailDomainBlocked: [(s) => [s.user], (user: UserType | null) => isPublicEmailDomain(user?.email)],
        domainFromEmail: [
            (s) => [s.userEmailDomain, s.isEmailDomainBlocked],
            (userEmailDomain: string, isEmailDomainBlocked: boolean) => (isEmailDomainBlocked ? '' : userEmailDomain),
        ],
        shouldShowEmailDomainBlockedGate: [
            (s) => [
                s.billing,
                s.formSubmitted,
                s.isAdminOrOwner,
                s.isAnnualPlanCustomer,
                s.isCurrentlyOnStartupPlan,
                s.isEmailDomainBlocked,
                s.isYC,
                s.wasPreviouslyOnStartupPlan,
            ],
            (
                billing: BillingType | null,
                formSubmitted: boolean,
                isAdminOrOwner: boolean | null,
                isAnnualPlanCustomer: boolean,
                isCurrentlyOnStartupPlan: boolean,
                isEmailDomainBlocked: boolean,
                isYC: boolean,
                wasPreviouslyOnStartupPlan: boolean
            ): boolean => {
                return (
                    !!billing &&
                    !formSubmitted &&
                    isAdminOrOwner === true &&
                    !isAnnualPlanCustomer &&
                    !isCurrentlyOnStartupPlan &&
                    !(wasPreviouslyOnStartupPlan && !isYC) &&
                    isEmailDomainBlocked
                )
            },
        ],
        ycBatchOptions: [
            () => [],
            () => {
                return getYCBatchOptions()
            },
        ],
    }),
    forms(({ values, actions, props }) => ({
        startupProgram: {
            defaults: {
                type: values.isYC ? StartupProgramType.YC : StartupProgramType.Startup,
                startup_domain: values.domainFromEmail || '',
                organization_name: values.currentOrganization!.name,
                organization_id: values.currentOrganizationId,
                raised: undefined,
                incorporation_date: undefined,
                yc_verification_url: values.isYC ? '' : undefined,
                yc_batch: values.isYC ? '' : undefined,
                yc_proof_screenshot_url: undefined,
                yc_merch_count: values.isYC ? 1 : undefined,
            } as StartupProgramFormValues,
            // Selector-style errors so that validation recomputes when billing
            // or isYC change, not only when form values change
            errors: [
                (s) => [s.startupProgram, s.billing, s.isYC, s.isEmailDomainBlocked],
                (
                    {
                        organization_id,
                        raised,
                        incorporation_date,
                        yc_verification_url,
                        yc_batch,
                        yc_proof_screenshot_url,
                    }: StartupProgramFormValues,
                    billing: BillingType | null,
                    isYC: boolean,
                    isEmailDomainBlocked: boolean
                ) => {
                    if (isEmailDomainBlocked) {
                        return {
                            _form: 'The startup program requires a company email address. Update your account email to your company domain, then apply again.',
                        }
                    }

                    if (!billing?.has_active_subscription) {
                        return {
                            _form: 'You need to upgrade to a paid plan before submitting your application',
                        }
                    }

                    return {
                        organization_id: !organization_id ? 'Please select an organization' : undefined,
                        raised: validateFunding(raised, isYC),
                        incorporation_date: validateIncorporationDate(incorporation_date, isYC),
                        yc_verification_url: validateYcVerificationUrl(yc_verification_url, isYC),
                        yc_batch: isYC && !yc_batch ? 'Please select your YC batch' : undefined,
                        yc_proof_screenshot_url:
                            isYC && !yc_proof_screenshot_url ? 'Please upload a screenshot' : undefined,
                    }
                },
            ],
            submit: async (formValues: StartupProgramFormValues) => {
                const valuesToSubmit: Record<string, any> = {
                    program: values.isYC ? StartupProgramType.YC : StartupProgramType.Startup,
                    organization_id: formValues.organization_id,
                    yc_merch_count: formValues.yc_merch_count,
                }

                if (values.isYC) {
                    valuesToSubmit.yc_verification_url = normalizeYcVerificationUrl(formValues.yc_verification_url)
                    valuesToSubmit.yc_batch = formValues.yc_batch
                    valuesToSubmit.yc_proof_screenshot_url = formValues.yc_proof_screenshot_url
                }

                if (!values.isYC) {
                    valuesToSubmit.raised = formValues.raised
                    valuesToSubmit.incorporation_date = dayjs.isDayjs(formValues.incorporation_date)
                        ? formValues.incorporation_date.format('YYYY-MM-DD')
                        : undefined
                    if (props.referrer) {
                        valuesToSubmit.referrer = props.referrer.toLowerCase()
                    }
                }

                try {
                    await api.create('api/billing/startups/apply', valuesToSubmit)
                    actions.setFormSubmitted(true)
                    // The verification link is bearer proof of YC founder status, so it stays out of analytics
                    const { yc_verification_url: _discarded, ...capturedValues } = valuesToSubmit
                    posthog.capture('startup program application submitted', capturedValues)
                } catch (error: any) {
                    // Billing-service validation errors can arrive as an object under error.detail
                    const detail = typeof error.detail === 'string' ? error.detail : error.detail?.detail
                    lemonToast.error(detail || 'Failed to submit application')
                    throw error
                }
            },
        },
    })),
    subscriptions(({ values, cache }) => ({
        shouldShowEmailDomainBlockedGate: () => {
            captureBlockedApplicationIfGateShown(values, cache)
        },
    })),
    afterMount(({ values, cache }) => {
        captureBlockedApplicationIfGateShown(values, cache)
    }),
])
