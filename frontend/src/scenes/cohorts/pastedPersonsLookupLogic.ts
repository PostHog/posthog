import { MakeLogicType, actions, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'

import { hogql } from '~/queries/utils'

export const MAX_PASTED_VALUES = 1000

const EMAIL_PATTERN = /^[^@\s]+@[^@.\s]+(?:\.[^@.\s]+)+$/

/**
 * Returns the values of a pasted list of emails or distinct IDs, or null when the text is a normal search.
 * Commas alone do not make a list unless every value is an email, so "Smith, John" stays a search.
 */
export function parsePastedPersonValues(text: string): string[] | null {
    const cleanToken = (token: string): string => token.replace(/^["'<]+|["'>]+$/g, '')
    const isBracketed = (token: string): boolean => token.startsWith('<') && token.endsWith('>')
    const parseEntry = (entry: string): string[] => {
        const tokens = entry.split(/[\s,]+/).filter((token) => cleanToken(token).length > 0)
        // In a "Name <address>" entry the display name identifies nobody, so only addresses are looked up
        if (tokens.some(isBracketed)) {
            return tokens.filter((token) => isBracketed(token) || EMAIL_PATTERN.test(cleanToken(token))).map(cleanToken)
        }
        // Commas and spaces separate emails, but a distinct ID can contain them
        if (tokens.every((token) => EMAIL_PATTERN.test(cleanToken(token)))) {
            return tokens.map(cleanToken)
        }
        const value = cleanToken(entry.trim())
        return value ? [value] : []
    }
    const values = Array.from(new Set(text.split(/[\n\r\t;]+/).flatMap(parseEntry)))
    if (values.length < 2) {
        return null
    }
    const hasLineSeparator = /[\n\r\t;]/.test(text.trim())
    if (!hasLineSeparator && !values.every((value) => EMAIL_PATTERN.test(value))) {
        return null
    }
    return values
}

export interface PastedPersonsMatch {
    personId: string
    value: string
}

export interface PastedPersonsLookupResult {
    matches: PastedPersonsMatch[]
    unmatched: string[]
    alreadyInCohortCount: number
    truncated: boolean
}

export interface PastedPersonsLookupLogicProps {
    dataNodeKey: string
    onAddPerson: (id: string, displayName: string | null) => void
    existingPersonsSet?: Set<string>
}

