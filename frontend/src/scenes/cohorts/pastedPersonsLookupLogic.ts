export type pastedPersonsLookupLogicType = MakeLogicType<
    pastedPersonsLookupLogicValues,
    pastedPersonsLookupLogicActions,
    PastedPersonsLookupLogicProps,
    pastedPersonsLookupLogicMeta
>

export const pastedPersonsLookupLogic = kea<pastedPersonsLookupLogicType>([
    props({} as PastedPersonsLookupLogicProps),
    path(['scenes', 'cohorts', 'pastedPersonsLookupLogic']),
    key((props) => props.dataNodeKey),
    actions({
        dismissLookupResult: true,
    }),
    loaders(({ props }) => ({
        lookupResult: [
            null as PastedPersonsLookupResult | null,
            {
                lookupPastedValues: async (values: string[]): Promise<PastedPersonsLookupResult> => {
                    const checkedValues = values.slice(0, MAX_PASTED_VALUES)
                    const lowerCaseValues = checkedValues.map((value) => value.toLowerCase())
                    const tags = { scene: 'Cohort', productKey: 'cohorts' }
                    // HogQL returns 100 rows unless the query sets a limit. Each query returns at most one row per value.
                    const rowLimit = checkedValues.length
                    const [byEmail, byDistinctId] = await Promise.all([
                        api.queryHogQL<[string, string[]]>(
                            hogql`SELECT lower(toString(properties.email)) AS email, groupArray(id) FROM persons WHERE has(${lowerCaseValues}, lower(toString(properties.email))) GROUP BY email LIMIT ${rowLimit}`,
                            tags
                        ),
                        api.queryHogQL<[string, string]>(
                            hogql`SELECT person_id, distinct_id FROM person_distinct_ids WHERE has(${checkedValues}, distinct_id) LIMIT ${rowLimit}`,
                            tags
                        ),
                    ])

                    const personIdsByValue = new Map<string, string[]>()
                    for (const [email, personIds] of byEmail.results ?? []) {
                        personIdsByValue.set(email, personIds)
                    }
                    for (const [personId, distinctId] of byDistinctId.results ?? []) {
                        personIdsByValue.set(distinctId, [personId])
                    }

                    const matches: PastedPersonsMatch[] = []
                    const unmatched: string[] = []
                    const matchedPersonIds = new Set<string>()
                    for (const value of checkedValues) {
                        const personIds = personIdsByValue.get(value) ?? personIdsByValue.get(value.toLowerCase())
                        if (!personIds) {
                            unmatched.push(value)
                            continue
                        }
                        for (const personId of personIds) {
                            if (!matchedPersonIds.has(personId)) {
                                matchedPersonIds.add(personId)
                                matches.push({ personId, value })
                            }
                        }
                    }
                    const alreadyInCohortCount = matches.filter(({ personId }) =>
                        props.existingPersonsSet?.has(personId)
                    ).length
                    return { matches, unmatched, alreadyInCohortCount, truncated: values.length > checkedValues.length }
                },
            },
        ],
    })),
    reducers({
        lookupResult: {
            dismissLookupResult: () => null,
        },
    }),
    listeners(({ props }) => ({
        lookupPastedValuesSuccess: ({ lookupResult, payload }) => {
            for (const { personId, value } of lookupResult.matches) {
                if (!props.existingPersonsSet?.has(personId)) {
                    props.onAddPerson(personId, value)
                }
            }
            posthog.capture('cohort persons list pasted', {
                source: props.dataNodeKey,
                value_count: payload?.length ?? 0,
                matched_count: lookupResult.matches.length,
                already_in_cohort_count: lookupResult.alreadyInCohortCount,
                unmatched_count: lookupResult.unmatched.length,
                truncated: lookupResult.truncated,
            })
        },
    })),
])
