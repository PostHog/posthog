import { MakeLogicType, actions, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'

import { hogql } from '~/queries/utils'

export const MAX_PASTED_VALUES = 1000

const EMAIL_PATTERN = /^[^@\s]+@[^@\s]+\.[^@\s]+$/

/**
 * Returns the values of a pasted list of emails or distinct IDs, or null when the text is a normal search.
 * Commas alone do not make a list unless every value is an email, so "Smith, John" stays a search.
 */
export function parsePastedPersonValues(text: string): string[] | null {
    const values = Array.from(
        new Set(
            text
                .split(/[\s,;]+/)
                .map((value) => value.trim().replace(/^["'<]+|["'>]+$/g, ''))
                .filter((value) => value.length > 0)
        )
    )
    if (values.length < 2) {
        return null
    }
    const hasLineSeparator = /[\n\r\t;]/.test(text.trim())
    if (!hasLineSeparator && !values.every((value) => EMAIL_PATTERN.test(value))) {
        return null
    }
    return values
}

export interface PastedPersonsMatch {
    personId: string
    value: string
}

export interface PastedPersonsLookupResult {
    matches: PastedPersonsMatch[]
    unmatched: string[]
    alreadyInCohortCount: number
    truncated: boolean
}

export interface PastedPersonsLookupLogicProps {
    dataNodeKey: string
    onAddPerson: (id: string, displayName: string | null) => void
    existingPersonsSet?: Set<string>
}

