const ADD_TO_NOTEBOOK_ACTION_ID = 'add-to-notebook'

function captureFocusClosed(cell: NotebookAnalyzeCell | undefined, via: 'card' | 'chip'): void {
    if (!cell) {
        return
    }
    // pinned: analytics event name, renaming it breaks dashboards
    posthog.capture('notebook analyze focus closed', {
        short_id: cell.notebookShortId,
        node_type: cell.nodeType,
        via,
    })
}

/**
 * "Analyze with PostHog AI" on a notebook cell: attaches the cell to the PostHog AI side panel, and
 * puts an "Add to notebook" button on every result the agent produces. A reader asks the next
 * question and keeps the answer without leaving the notebook.
 *
 * The registrations live as long as the notebook is on screen, not as long as the panel is open, so
 * a run keeps its context and its way back into the notebook while the reader reads the answer.
 */
export const notebookAnalyzeLogic = kea<notebookAnalyzeLogicType>([
    props({} as NotebookAnalyzeLogicProps),
    key((props) => props.notebookLogic.props.shortId),
    path((key) => ['scenes', 'notebooks', 'Notebook', 'notebookAnalyzeLogic', key]),

    connect((props: NotebookAnalyzeLogicProps) => ({
        values: [
            props.notebookLogic,
            ['content', 'title', 'canEditNotebook', 'isEditable', 'isShared'],
            maxGlobalLogic,
            ['effectivePhaiView', 'isMaxAvailable'],
            featureFlagLogic,
            ['featureFlags'],
            composerFocusLogic,
            ['focus'],
        ],
        actions: [
            attachedContextLogic,
            ['registerContext', 'deregisterContext', 'undismissContext', 'dismissContext'],
            artifactActionsLogic,
            ['registerArtifactAction', 'deregisterArtifactAction'],
            composerFocusLogic,
            ['registerFocus', 'deregisterFocus', 'closeFocus'],
            welcomeOverrideLogic,
            ['registerHeadlines', 'deregisterHeadlines'],
            sidePanelStateLogic,
            ['openSidePanel'],
        ],
    })),

    actions({
        startAnalysis: (cell: NotebookAnalyzeCell) => ({ cell }),
        addResultToNotebook: (payload: VisualizationArtifactActionPayload) => ({ payload }),
    }),

    reducers({
        session: [
            null as { cell: NotebookAnalyzeCell } | null,
            {
                startAnalysis: (_, { cell }) => ({ cell }),
            },
        ],
    }),

    selectors({
        analyzeEnabled: [
            (s) => [s.featureFlags, s.effectivePhaiView, s.isMaxAvailable, s.isShared],
            (
                featureFlags: FeatureFlagsSet,
                effectivePhaiView: PhaiViewMode,
                isMaxAvailable: boolean,
                isShared: boolean
            ): boolean =>
                !!featureFlags[FEATURE_FLAGS.NOTEBOOK_AI_ANALYZE_MORE] &&
                effectivePhaiView === 'new' &&
                isMaxAvailable &&
                !isShared,
        ],
    }),

    listeners(({ actions, values, props, cache }) => ({
        startAnalysis: ({ cell }) => {
            // Built from the content already in memory, so opening the panel costs no fetch.
            const outline = isMarkdownNotebookContent(values.content)
                ? buildNotebookOutline(
                      parseMarkdownNotebook(getMarkdownNotebookMarkdown(values.content)).nodes,
                      cell.nodeId
                  )
                : undefined
            const items = buildNotebookAnalyzeContext(cell, values.title, outline)
            // A chip the reader closed earlier stays closed, so restore the set first: analyzing a
            // cell is an explicit request for its context.
            for (const item of items) {
                actions.undismissContext(attachedContextItemKey(item), item.dismissGroup)
            }
            // Analyzing a second cell re-adds under the same key, which disposes the first cell's
            // registration. `pauseOnPageHidden: false`, because a hide-paused registration would drop
            // the cell from a message the reader queued before the tab went to the background.
            cache.disposables.add(
                () => {
                    actions.registerContext(NOTEBOOK_ANALYZE_PROVIDER_ID, items)
                    return () => actions.deregisterContext(NOTEBOOK_ANALYZE_PROVIDER_ID)
                },
                'analyzeContext',
                { pauseOnPageHidden: false }
            )

            if (values.canEditNotebook) {
                cache.disposables.add(
                    () => {
                        actions.registerArtifactAction(NOTEBOOK_ANALYZE_PROVIDER_ID, {
                            id: ADD_TO_NOTEBOOK_ACTION_ID,
                            label: 'Add to notebook',
                            icon: <IconNotebook />,
                            onSelect: actions.addResultToNotebook,
                        })
                        return () => actions.deregisterArtifactAction(NOTEBOOK_ANALYZE_PROVIDER_ID)
                    },
                    'analyzeArtifactAction',
                    { pauseOnPageHidden: false }
                )
            }

            const focus = buildNotebookAnalyzeFocus(cell)
            if (focus) {
                cache.disposables.dispose('analyzeHeadline')
                cache.disposables.add(
                    () => {
                        actions.registerFocus(NOTEBOOK_ANALYZE_PROVIDER_ID, focus)
                        return () => actions.deregisterFocus(NOTEBOOK_ANALYZE_PROVIDER_ID)
                    },
                    'analyzeFocus',
                    { pauseOnPageHidden: false }
                )
            } else {
                // No card replaces the welcome state, so its headline names the cell instead.
                cache.disposables.dispose('analyzeFocus')
                cache.disposables.add(
                    () => {
                        actions.registerHeadlines(NOTEBOOK_ANALYZE_PROVIDER_ID, [getNotebookAnalyzeHeadline(cell)])
                        return () => actions.deregisterHeadlines(NOTEBOOK_ANALYZE_PROVIDER_ID)
                    },
                    'analyzeHeadline',
                    { pauseOnPageHidden: false }
                )
            }

            // An open thread hides the composer, and with it the card and the prefilled prompt. Leaving
            // the thread keeps it in history, so the reader starts fresh on the cell they clicked.
            const sidePanelRunner = runnerPanelLogic.findMounted({ panelId: MAX_SIDE_PANEL_ID })
            const panelHadActiveRun = !!sidePanelRunner?.values.activeCreation
            if (panelHadActiveRun) {
                sidePanelRunner?.actions.clearActiveCreation()
            }

            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('notebook analyze more clicked', {
                short_id: cell.notebookShortId,
                node_type: cell.nodeType,
                cell_kind: cell.kind,
                has_insight_id: !!cell.insightShortId,
                notebook_mode: values.isEditable ? 'edit' : 'view',
                focus_shown: !!focus,
                panel_had_active_run: panelHadActiveRun,
            })

            // No leading `!`, so the panel prefills the prompt and waits for the reader to send it.
            actions.openSidePanel(SidePanelTab.Max, getNotebookAnalyzePrompt(cell))
        },

        closeFocus: ({ providerId }) => {
            if (providerId !== NOTEBOOK_ANALYZE_PROVIDER_ID) {
                return
            }
            // `composerFocusLogic` already deregistered the focus and dismissed the chips.
            cache.disposables.dispose('analyzeFocus')
            captureFocusClosed(values.session?.cell, 'card')
        },

        dismissContext: ({ dismissGroup }) => {
            // A card close also dismisses the group, but it deregisters the focus first, so only a
            // closed chip still finds the notebook's focus here.
            if (
                dismissGroup !== NOTEBOOK_ANALYZE_CONTEXT_GROUP ||
                values.focus?.providerId !== NOTEBOOK_ANALYZE_PROVIDER_ID
            ) {
                return
            }
            cache.disposables.dispose('analyzeFocus')
            captureFocusClosed(values.session?.cell, 'chip')
        },

        addResultToNotebook: ({ payload }) => {
            const cell = values.session?.cell
            if (!cell || !isMarkdownNotebookContent(values.content)) {
                return
            }

            const insertedCell = buildNotebookCellFromArtifact(payload, {
                sqlV2Enabled: !!values.featureFlags[FEATURE_FLAGS.REVAMPED_PY_NOTEBOOKS],
            })
            if (!insertedCell) {
                lemonToast.error('This result has no query to add. Open it as an insight instead.')
                return
            }

            // The converter serializes the children of a doc, so a single leaf node must be wrapped
            // in an array to be serialized itself.
            const markdown = convertNotebookContentToMarkdown([insertedCell])
            if (!markdown.trim()) {
                return
            }

            const appendedAtEnd = !hasMarkdownNotebookNode(values.content, cell.nodeId)
            props.notebookLogic.actions.setLocalContent(
                insertMarkdownNotebookBlockAfterNode(values.content, cell.nodeId, markdown)
            )
            lemonToast.success(
                appendedAtEnd
                    ? 'Added at the end. The cell you asked about is no longer in the notebook.'
                    : 'Added to the notebook'
            )

            // pinned: analytics event name, renaming it breaks dashboards
            posthog.capture('notebook ai result added', {
                short_id: cell.notebookShortId,
                source_node_type: cell.nodeType,
                inserted_node_type: insertedCell.type,
                tool_name: payload.toolName,
                appended_at_end: appendedAtEnd,
            })
        },
    })),
])
