/**
 * Runs every SQL and Python cell of a markdown notebook as one server-side run.
 *
 * The server owns the order and the stop-on-failure rule; this logic starts the run, follows
 * it, and hands each cell's run id to the cell that owns it. The cell then polls and writes
 * the result exactly as it does for its own Run button, so staleness marks and result tables
 * need no new code.
 */
export const notebookRunLogic = kea<notebookRunLogicType>([
    props({} as NotebookRunLogicProps),
    key((props) => props.shortId),
    path((key) => ['scenes', 'notebooks', 'Notebook', 'notebookRunLogic', key]),
    connect((props: NotebookRunLogicProps) => ({
        values: [notebookOperationsLogic({ shortId: props.shortId }), ['isBusy'], teamLogic, ['currentTeamId']],
        actions: [
            notebookOperationsLogic({ shortId: props.shortId }),
            ['startOperation', 'finishOperation'],
            notebookNodeStalenessLogic({ shortId: props.shortId }),
            ['adoptChainRun'],
        ],
    })),
    actions({
        startRun: true,
        setStarted: (runId: string, cellCount: number) => ({ runId, cellCount }),
        pollRun: true,
        setRun: (run: NotebookRunStatusResponseApi) => ({ run }),
        runFinished: (run: NotebookRunStatusResponseApi) => ({ run }),
        interruptRun: true,
        stopTracking: true,
    }),
    reducers({
        isStarting: [
            false,
            {
                startRun: () => true,
                setStarted: () => false,
                stopTracking: () => false,
            },
        ],
        runId: [
            null as string | null,
            {
                setStarted: (_, { runId }) => runId,
                stopTracking: () => null,
            },
        ],
        cellCount: [
            0,
            {
                setStarted: (_, { cellCount }) => cellCount,
                stopTracking: () => 0,
            },
        ],
        run: [
            null as NotebookRunStatusResponseApi | null,
            {
                startRun: () => null,
                setRun: (_, { run }) => run,
                stopTracking: () => null,
            },
        ],
        startedAt: [
            null as number | null,
            {
                startRun: () => Date.now(),
                stopTracking: () => null,
            },
        ],
    }),
    selectors({
        isRunning: [
            (s) => [s.run, s.isStarting],
            (run: NotebookRunStatusResponseApi | null, isStarting: boolean): boolean =>
                isStarting || run?.status === 'running',
        ],
        currentNodeId: [
            (s) => [s.run],
            (run: NotebookRunStatusResponseApi | null): string | null => run?.current_node_id ?? null,
        ],
        progressLabel: [
            (s) => [s.run, s.cellCount],
            (run: NotebookRunStatusResponseApi | null, cellCount: number): string | null => {
                const total = cellCount || run?.cells.length || 0
                if (!run || run.status !== 'running' || !total) {
                    return null
                }
                return `Running cell ${Math.min(run.current_index + 1, total)} of ${total}`
            },
        ],
    }),
    listeners(({ props, actions, values, cache }) => ({
        startRun: async () => {
            const projectId = String(values.currentTeamId)
            try {
                const started = await notebooksRunsCreate(projectId, props.shortId)
                actions.setStarted(started.run_id, started.cell_count)
                posthog.capture('notebook run all started', {
                    cell_count: started.cell_count,
                    starts_sandbox: started.starts_sandbox,
                    trigger: 'ui',
                })
                if (started.starts_sandbox) {
                    // The same disclosure a single Python cell makes. A whole-notebook run is
                    // the easier one to start without noticing it provisions paid compute.
                    lemonToast.info(
                        started.sandbox_hourly_price == null
                            ? 'Starting a compute sandbox. The notebook will run once it’s ready.'
                            : `Starting a compute sandbox at $${started.sandbox_hourly_price.toFixed(2)} / h while it runs.`
                    )
                }
                actions.startOperation(runAllOperation)
                actions.pollRun()
            } catch (error) {
                actions.stopTracking()
                lemonToast.error(notebookRunErrorMessage(error))
            }
        },
        pollRun: async () => {
            const runId = values.runId
            if (!runId) {
                return
            }
            let run: NotebookRunStatusResponseApi
            try {
                run = await notebooksRunsRetrieve(String(values.currentTeamId), props.shortId, runId)
            } catch {
                // A single failed poll is not a failed run — the next tick reads it again.
                cache.disposables.add(() => {
                    const timeout = window.setTimeout(() => actions.pollRun(), POLL_INTERVAL_MS)
                    return () => clearTimeout(timeout)
                }, 'pollRun')
                return
            }
            if (values.runId !== runId) {
                // Interrupted, or a newer run took over while this poll was in flight.
                return
            }
            actions.setRun(run)
            for (const cell of run.cells) {
                if (cell.run_id) {
                    // Idempotent on the cell's side: adopting a run it already polls is a no-op.
                    actions.adoptChainRun(cell.node_id, cell.run_id)
                }
            }
            if (run.status !== 'running') {
                actions.runFinished(run)
                return
            }
            cache.disposables.add(() => {
                const timeout = window.setTimeout(() => actions.pollRun(), POLL_INTERVAL_MS)
                return () => clearTimeout(timeout)
            }, 'pollRun')
        },
        runFinished: ({ run }) => {
            cache.disposables.dispose('pollRun')
            actions.finishOperation(runAllOperation.id)
            const failedCell = run.cells.find((cell) => cell.node_id === run.failed_node_id)
            posthog.capture('notebook run all finished', {
                cell_count: run.cells.length,
                python_cell_count: run.cells.filter((cell) => cell.cell_type === 'python').length,
                outcome: run.status,
                duration_ms: values.startedAt ? Date.now() - values.startedAt : null,
                trigger: 'ui',
            })
            if (run.status === 'done') {
                lemonToast.success('The notebook finished running.')
            } else if (run.status === 'interrupted') {
                lemonToast.info('The run was stopped.')
            } else {
                const name = failedCell?.dataframe_name || describeCellPosition(run, run.failed_node_id)
                lemonToast.error(name ? `${name} failed, so the run stopped there.` : 'The run failed.')
            }
        },
        interruptRun: async () => {
            const runId = values.runId
            if (!runId) {
                return
            }
            cache.disposables.dispose('pollRun')
            try {
                await notebooksRunsInterruptCreate(String(values.currentTeamId), props.shortId, runId)
            } catch (error) {
                lemonToast.error(notebookRunErrorMessage(error))
            }
            // Read the run back rather than assume the stop landed: an interrupt that lost the
            // race to a finish must report the outcome the run actually reached.
            actions.pollRun()
        },
        stopTracking: () => {
            cache.disposables.dispose('pollRun')
            actions.finishOperation(runAllOperation.id)
        },
    })),
])

/** Which cell a failure names, when it has no dataframe name to go by. */
function describeCellPosition(run: NotebookRunStatusResponseApi, nodeId: string | null | undefined): string | null {
    if (!nodeId) {
        return null
    }
    const index = run.cells.findIndex((cell) => cell.node_id === nodeId)
    return index === -1 ? null : `Cell ${index + 1}`
}

function notebookRunErrorMessage(error: unknown): string {
    const detail = (error as { data?: { detail?: string }; detail?: string } | null)?.data?.detail
    return detail || (error as { detail?: string } | null)?.detail || 'Could not run the notebook.'
}
