export const notebookNodeCanvasLogic: LogicWrapper<notebookNodeCanvasLogicType> = kea<notebookNodeCanvasLogicType>([
    props({} as NotebookNodeCanvasLogicProps),
    key((props) => props.nodeId),
    path((key) => ['scenes', 'notebooks', 'Nodes', 'notebookNodeCanvasLogic', key]),
    connect(() => ({ values: [teamLogic, ['currentTeamId']] })),
    actions({
        approveDataAccess: true,
        createFromPrompt: true,
        createFromPromptSuccess: (canvasId: string, taskId: string) => ({ canvasId, taskId }),
        createFromPromptFailure: (error: string) => ({ error }),
        generationFailed: (error: string) => ({ error }),
        setRuntimeError: (error: string | null) => ({ error }),
        setEditedCode: (code: string) => ({ code }),
        buildFinished: true,
        discardSourceChanges: true,
        resetDataAccessApproval: true,
        watchGeneration: (canvasId: string, taskId: string) => ({ canvasId, taskId }),
    }),
    loaders(({ props, values }) => ({
        canvas: [
            null as CanvasApi | null,
            {
                loadCanvas: async () => await canvasesRetrieve(String(values.currentTeamId), props.id),
            },
        ],
        builds: [
            null as CanvasBuildsResponseApi | null,
            {
                loadBuilds: async () => await canvasesBuildsRetrieve(String(values.currentTeamId), props.id),
            },
        ],
        source: [
            null as CanvasSourceResponseApi | null,
            {
                loadSource: async () => await canvasesSourceRetrieve(String(values.currentTeamId), props.id),
            },
        ],
        publishResult: [
            null as CanvasSourcePublishResponseApi | null,
            {
                publishSource: async () => {
                    const source = values.source
                    if (!source) {
                        throw new Error('Canvas source is not loaded yet')
                    }
                    return await canvasesPublishCreate(String(values.currentTeamId), props.id, {
                        project: {
                            ...source.project,
                            files: { ...source.project.files, [CANVAS_COMPONENT_PATH]: values.sourceCode },
                        },
                        prompt: 'Edited in notebook',
                        expected_current_version_id: source.current_version_id,
                    })
                },
            },
        ],
    })),
    reducers({
        creatingCanvas: [
            false,
            {
                createFromPrompt: () => true,
                createFromPromptSuccess: () => false,
                createFromPromptFailure: () => false,
            },
        ],
        canvasCreationError: [
            null as string | null,
            {
                createFromPrompt: () => null,
                createFromPromptSuccess: () => null,
                createFromPromptFailure: (_, { error }) => error,
            },
        ],
        generationError: [
            null as string | null,
            {
                createFromPrompt: () => null,
                generationFailed: (_, { error }) => error,
            },
        ],
        canvasMissing: [
            false,
            {
                loadCanvas: () => false,
                loadCanvasFailure: (_, { errorObject }: { errorObject?: unknown }) =>
                    errorObject instanceof ApiError && errorObject.status === 404,
                loadCanvasSuccess: () => false,
            },
        ],
        runtimeError: [
            null as string | null,
            {
                setRuntimeError: (_, { error }) => error,
            },
        ],
        dataAccessApproved: [
            false,
            {
                approveDataAccess: () => true,
                resetDataAccessApproval: () => false,
            },
        ],
        editedCode: [
            null as string | null,
            {
                setEditedCode: (_, { code }) => code,
                discardSourceChanges: () => null,
                publishSourceSuccess: () => null,
            },
        ],
        publishDiagnostics: [
            [] as CanvasDiagnosticApi[],
            {
                publishSource: () => [],
                publishSourceSuccess: () => [],
                publishSourceFailure: (_, { errorObject }: { errorObject?: unknown }) => {
                    const diagnostics = (errorObject as { data?: { diagnostics?: CanvasDiagnosticApi[] } } | undefined)
                        ?.data?.diagnostics
                    return Array.isArray(diagnostics) ? diagnostics : []
                },
            },
        ],
        buildingVersionId: [
            null as string | null,
            {
                publishSourceSuccess: (_, { publishResult }) => publishResult.current_version_id,
                buildFinished: () => null,
            },
        ],
    }),
    selectors({
        publishedBuild: [
            (s) => [s.builds],
            (builds: CanvasBuildsResponseApi | null): CanvasBuildApi | null =>
                builds?.builds.find((build) => build.id === builds.published_build_id) ?? null,
        ],
        artifactUrl: [
            (s) => [s.publishedBuild],
            (publishedBuild: CanvasBuildApi | null): string | null => publishedBuild?.artifact_url ?? null,
        ],
        capabilities: [
            (s) => [s.publishedBuild],
            (publishedBuild: CanvasBuildApi | null): CanvasCapabilities | undefined =>
                parseCanvasCapabilities(publishedBuild?.manifest?.capabilities),
        ],
        savedCode: [
            (s) => [s.source],
            (source: CanvasSourceResponseApi | null): string => {
                const file = source?.project.files[CANVAS_COMPONENT_PATH]
                return typeof file === 'string' ? file : ''
            },
        ],
        sourceCode: [
            (s) => [s.editedCode, s.savedCode],
            (editedCode: string | null, savedCode: string): string => editedCode ?? savedCode,
        ],
        hasSourceChanges: [
            (s) => [s.editedCode, s.savedCode],
            (editedCode: string | null, savedCode: string): boolean => editedCode !== null && editedCode !== savedCode,
        ],
        isBuilding: [
            (s) => [s.buildingVersionId],
            (buildingVersionId: string | null): boolean => buildingVersionId !== null,
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        createFromPrompt: async () => {
            if (!props.isEditable) {
                actions.createFromPromptFailure('You need edit access to create this canvas.')
                return
            }
            if (cache.initializingFromPrompt) {
                return
            }

            const instruction = props.prompt.trim()
            if (!instruction) {
                actions.createFromPromptFailure('Add a prompt before creating a canvas.')
                return
            }

            cache.initializingFromPrompt = true
            try {
                let canvas = values.canvas
                if (!canvas || canvas.id !== props.id) {
                    if (props.id) {
                        canvas = await canvasesRetrieve(String(values.currentTeamId), props.id)
                    } else {
                        let channelId = props.channelId
                        if (!channelId) {
                            const channels = await taskChannelsList(String(values.currentTeamId))
                            channelId = channels.find((channel) => channel.channel_type === 'personal')?.id
                        }
                        if (!channelId) {
                            throw new Error("Couldn't find a personal channel. Refresh and try again.")
                        }
                        canvas = await canvasesCreate(String(values.currentTeamId), {
                            name: getCanvasNameFromPrompt(instruction),
                            channel_id: channelId,
                        })
                        props.updateAttributes({ id: canvas.id, channelId: canvas.channel })
                    }
                }

                const prompt = buildCanvasGenerationPrompt({
                    canvasId: canvas.id,
                    name: canvas.name,
                    channelId: canvas.channel,
                    instruction,
                    isEdit: !!canvas.published_build_id,
                })
                const task = await tasksCreate(String(values.currentTeamId), {
                    title: `${canvas.published_build_id ? 'Update' : 'Build'} canvas "${canvas.name}"`,
                    description: prompt,
                    channel: canvas.channel,
                })
                const updatedCanvas = await canvasesPartialUpdate(String(values.currentTeamId), canvas.id, {
                    context: instruction,
                    generation_task_id: task.id,
                })
                await tasksRunCreate(String(values.currentTeamId), task.id, {
                    mode: TaskExecutionModeEnumApi.Background,
                    pending_user_message: prompt,
                })
                actions.loadCanvasSuccess(updatedCanvas)
                actions.createFromPromptSuccess(canvas.id, task.id)
                lemonToast.success('Canvas generation started', {
                    button: { label: 'View task', action: () => router.actions.push(urls.taskDetail(task.id)) },
                })
            } catch (error) {
                const errorObject = error instanceof Error ? error : new Error(String(error))
                posthog.captureException(errorObject, { action: 'create notebook canvas from prompt' })
                actions.createFromPromptFailure(errorObject.message)
            } finally {
                cache.initializingFromPrompt = false
            }
        },
        discardSourceChanges: () => {
            actions.loadSource()
        },
        publishSourceSuccess: async ({ publishResult }, breakpoint) => {
            actions.loadSource()
            // Poll the build lifecycle until this publish's build lands, so the
            // rendered iframe swaps to the new artifact without a manual refresh.
            for (let attempt = 0; attempt < BUILD_POLL_MAX_ATTEMPTS; attempt++) {
                await breakpoint(BUILD_POLL_INTERVAL_MS)
                let builds: CanvasBuildsResponseApi
                try {
                    builds = await canvasesBuildsRetrieve(String(values.currentTeamId), props.id)
                } catch {
                    continue
                }
                breakpoint()
                actions.loadBuildsSuccess(builds)
                const build = builds.builds.find((b) => b.source_version_id === publishResult.current_version_id)
                if (build?.build_status === 'ready') {
                    actions.buildFinished()
                    actions.loadCanvas()
                    lemonToast.success('Canvas published')
                    return
                }
                if (build?.build_status === 'failed') {
                    actions.buildFinished()
                    lemonToast.error('The canvas build failed. Check the diagnostics in the edit panel.')
                    return
                }
            }
            actions.buildFinished()
            lemonToast.error('The canvas build is taking longer than expected. Reload to check its status.')
        },
        publishSourceFailure: ({ errorObject }: { errorObject?: unknown }) => {
            if (errorObject instanceof ApiError && errorObject.status === 409) {
                actions.loadSource()
                lemonToast.error(
                    'The canvas changed elsewhere. Review your edit against the latest source and publish again.'
                )
            }
        },
        loadCanvasSuccess: ({ canvas }) => {
            if (canvas.generation_task_id && !canvas.published_build_id) {
                actions.watchGeneration(canvas.id, canvas.generation_task_id)
            }
        },
        watchGeneration: async ({ canvasId, taskId }, breakpoint) => {
            const initialBuildId = values.builds?.published_build_id ?? null
            for (let attempt = 0; attempt < AGENT_POLL_MAX_ATTEMPTS; attempt++) {
                if (attempt > 0) {
                    await breakpoint(AGENT_POLL_INTERVAL_MS)
                }
                let builds: CanvasBuildsResponseApi
                let task: TaskDetailDTOApi
                try {
                    const [loadedBuilds, loadedTask] = await Promise.all([
                        canvasesBuildsRetrieve(String(values.currentTeamId), canvasId),
                        tasksRetrieve(String(values.currentTeamId), taskId),
                    ])
                    builds = loadedBuilds
                    task = loadedTask
                } catch {
                    continue
                }
                breakpoint()
                actions.loadBuildsSuccess(builds)
                if (builds.published_build_id && builds.published_build_id !== initialBuildId) {
                    actions.loadCanvas()
                    actions.loadSource()
                    lemonToast.success('Canvas updated')
                    return
                }
                if (task.latest_run?.status === 'failed' || task.latest_run?.status === 'cancelled') {
                    actions.generationFailed(
                        task.latest_run.error_message?.trim()
                            ? `Couldn't build this canvas: ${task.latest_run.error_message}`
                            : "Couldn't build this canvas. Try again."
                    )
                    return
                }
                if (task.latest_run?.status === 'completed' && !builds.current_version_id) {
                    actions.generationFailed('The generation task finished without publishing the canvas. Try again.')
                    return
                }
            }
            actions.generationFailed(
                'Canvas generation is taking longer than expected. Open the generation task to check its progress.'
            )
        },
    })),
    afterMount(({ actions, props }) => {
        if (props.id) {
            actions.loadCanvas()
            actions.loadBuilds()
        }
    }),
    propsChanged(({ actions, props }, oldProps) => {
        if (props.id !== oldProps.id) {
            actions.resetDataAccessApproval()
            if (props.id) {
                actions.loadCanvas()
                actions.loadBuilds()
            }
        }
    }),
])
