const BUILD_POLL_INTERVAL_MS = 2000
const BUILD_POLL_MAX_ATTEMPTS = 90
// The agent needs minutes to edit and publish, so its poll is slower and longer.
const AGENT_POLL_INTERVAL_MS = 10_000
const AGENT_POLL_MAX_ATTEMPTS = 90
const GENERATED_CANVAS_NAME_MAX_LENGTH = 80

export function getCanvasNameFromPrompt(prompt: string): string {
    const normalizedPrompt = prompt.trim().replace(/\s+/g, ' ')
    if (normalizedPrompt.length <= GENERATED_CANVAS_NAME_MAX_LENGTH) {
        return normalizedPrompt
    }
    return `${normalizedPrompt.slice(0, GENERATED_CANVAS_NAME_MAX_LENGTH - 3).trimEnd()}...`
}

