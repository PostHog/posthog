const isSqlQueryNode = (nodeAttributes: NotebookNodeAttributes<any>): boolean => {
    const query = nodeAttributes?.query
    if (!query) {
        return false
    }
    if (isHogQLQuery(query)) {
        return true
    }
    if (isNodeWithSource(query)) {
        return isHogQLQuery(query.source)
    }
    return false
}

