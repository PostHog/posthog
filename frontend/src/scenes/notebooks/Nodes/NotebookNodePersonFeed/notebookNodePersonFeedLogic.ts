import { NodeKind, SessionsTimelineQuery, SessionsTimelineQueryResponse } from '~/queries/schema/schema-general'
import { setLatestVersionsOnQuery } from '~/queries/utils'

import { CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS } from 'products/customer_analytics/frontend/constants'

import type { TimelineEntry } from '../../../../queries/schema/schema-general'

export type NotebookNodePersonFeedLogicProps = {
    personId: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface notebookNodePersonFeedLogicValues {
    sessions: SessionsTimelineQueryResponse['results'] | null
    sessionsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface notebookNodePersonFeedLogicActions {
    loadSessionsTimeline: () => any
    loadSessionsTimelineFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSessionsTimelineSuccess: (
        sessions: TimelineEntry[],
        payload?: any
    ) => {
        sessions: TimelineEntry[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface notebookNodePersonFeedLogicMeta {
    key: string
}

export type notebookNodePersonFeedLogicType = MakeLogicType<
    notebookNodePersonFeedLogicValues,
    notebookNodePersonFeedLogicActions,
    NotebookNodePersonFeedLogicProps,
    notebookNodePersonFeedLogicMeta
>

export const notebookNodePersonFeedLogic = kea<notebookNodePersonFeedLogicType>([
    props({} as NotebookNodePersonFeedLogicProps),
    path((key) => ['scenes', 'notebooks', 'Notebook', 'Nodes', 'notebookNodePersonFeedLogic', key]),
    key(({ personId }) => personId),

    loaders(({ props }) => ({
        sessions: [
            null as SessionsTimelineQueryResponse['results'] | null,
            {
                loadSessionsTimeline: async () => {
                    const result = await performQuery<SessionsTimelineQuery>(
                        setLatestVersionsOnQuery({
                            kind: NodeKind.SessionsTimelineQuery,
                            tags: CUSTOMER_ANALYTICS_DEFAULT_QUERY_TAGS,
                            personId: props.personId,
                        })
                    )
                    return result.results
                },
            },
        ],
    })),

    afterMount(({ actions }) => {
        actions.loadSessionsTimeline()
    }),
])
