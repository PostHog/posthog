export const notebookSceneLogic = kea<notebookSceneLogicType>([
    path((key) => ['scenes', 'notebooks', 'notebookSceneLogic', key]),
    props({} as NotebookSceneLogicProps),
    key(({ shortId }) => shortId),
    connect((props: NotebookSceneLogicProps) => ({
        values: [
            notebookLogic(props),
            ['notebook', 'notebookLoading', 'isLocalOnly'],
            notebooksModel,
            ['notebooksLoading'],
        ],
        actions: [notebookLogic(props), ['loadNotebook', 'loadNotebookSuccess'], notebooksModel, ['createNotebook']],
    })),
    selectors(() => ({
        notebookId: [(_, p) => [p.shortId], (shortId: string) => shortId],

        loading: [
            (s) => [s.notebookLoading, s.notebooksLoading],
            (notebookLoading: boolean, notebooksLoading: boolean) => notebookLoading || notebooksLoading,
        ],

        breadcrumbs: [
            (s) => [s.notebook, s.loading, router.selectors.searchParams, featureFlagLogic.selectors.featureFlags],
            (
                notebook: NotebookType | null,
                loading: boolean,
                searchParams: Record<string, any>,
                featureFlags: FeatureFlagsSet
            ): Breadcrumb[] => {
                // The Analytics list that opened the notebook names the way back, like the dashboard scene allows.
                const backLink = analyticsBackLink(searchParams, featureFlags)
                const parent: Breadcrumb = backLink
                    ? {
                          key: backLink.url,
                          name: backLink.name,
                          path: backLink.url,
                          iconType: 'notebook',
                      }
                    : notebook?.parent_resource?.type === 'account'
                      ? {
                            key: Scene.CustomerAnalytics,
                            name: 'Accounts',
                            path: urls.customerAnalyticsAccount(notebook.parent_resource.id),
                            iconType: 'group',
                        }
                      : {
                            key: Scene.Notebooks,
                            name: 'Notebooks',
                            path: urls.notebooks(),
                            iconType: 'notebook',
                        }
                return [
                    parent,
                    {
                        key: [Scene.Notebook, notebook?.short_id || 'new'],
                        name: notebook ? notebook?.title || 'Unnamed' : loading ? null : 'Notebook not found',
                        iconType: 'notebook',
                    },
                ]
            },
        ],

        projectTreeRef: [
            () => [(_, props: NotebookSceneLogicProps) => props.shortId],
            (shortId: string): ProjectTreeRef | null =>
                shortId === 'new' ? null : { type: 'notebook', ref: String(shortId) },
        ],

        [SIDE_PANEL_CONTEXT_KEY]: [
            (s) => [s.notebookId, s.isLocalOnly],
            (notebookId: string, isLocalOnly: boolean): SidePanelSceneContext | null => {
                return notebookId && !isLocalOnly
                    ? {
                          activity_scope: ActivityScope.NOTEBOOK,
                          activity_item_id: notebookId,
                          access_control_resource: 'notebook',
                          access_control_resource_id: notebookId,
                      }
                    : null
            },
        ],
    })),

    listeners(({ cache }) => ({
        loadNotebookSuccess: () => restoreScrollPosition(cache),
    })),
    afterMount(({ actions, props, values, cache }) => {
        if (router.values.lastMethod === 'POP') {
            cache.scrollRestoreTarget = scrollPositions.get(props.shortId)
            if (values.notebook) {
                restoreScrollPosition(cache)
            }
        }
        // Navigating away resets the scroll position while this notebook is still rendered, so positions are
        // recorded while mounted, and only while the URL still points at this notebook.
        const pathname = router.values.location.pathname
        cache.disposables.add(() => {
            // Scroll events don't bubble, so a capturing listener sees the scene container even when it mounts later.
            const onScroll = (event: Event): void => {
                const element = getSceneScrollContainer()
                if (element && event.target === element && router.values.location.pathname === pathname) {
                    scrollPositions.set(props.shortId, element.scrollTop)
                }
            }
            document.addEventListener('scroll', onScroll, { capture: true, passive: true })
            return () => document.removeEventListener('scroll', onScroll, { capture: true })
        }, 'scrollTracking')
        // notebookLogic already revalidates a retained copy when it mounts.
        if (props.shortId !== 'new' && !values.notebookLoading) {
            actions.loadNotebook()
        }
    }),
])
