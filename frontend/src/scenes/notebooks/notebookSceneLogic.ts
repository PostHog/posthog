const MAX_SCROLL_RESTORE_FRAMES = 60
const scrollPositions = new Map<string, number>()

function getSceneScrollContainer(): HTMLElement | null {
    return panelLayoutLogic.findMounted()?.values.mainContentRef?.current ?? null
}

function restoreScrollPosition(cache: Record<string, any>): void {
    const target: number | undefined = cache.scrollRestoreTarget
    cache.scrollRestoreTarget = undefined
    if (!target) {
        return
    }
    let frames = 0
    const restore = (): void => {
        const element = getSceneScrollContainer()
        if (!element) {
            return
        }
        if (element.scrollHeight - element.clientHeight >= target || ++frames >= MAX_SCROLL_RESTORE_FRAMES) {
            element.scrollTop = target
            return
        }
        cache.disposables.add(() => {
            const id = requestAnimationFrame(restore)
            return () => cancelAnimationFrame(id)
        }, 'scrollRestore')
    }
    restore()
}
