import { MakeLogicType, afterMount, connect, kea, key, path, props } from 'kea'

import { databaseTableListLogic } from 'scenes/data-management/database/databaseTableListLogic'
import { materializationJobsLogic } from 'scenes/data-warehouse/saved_queries/materializationJobsLogic'

import type {
    DatabaseSchemaDataWarehouseTable,
    DatabaseSchemaTable,
    DatabaseSchemaViewTable,
    HogQLMetadataResponse,
} from '../../../../queries/schema/schema-general'
import { sqlEditorLogic } from '../sqlEditorLogic'

export interface InfoTabLogicProps {
    tabId: string
    viewId?: string
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface infoTabLogicValues {
    dataWarehouseTablesMap: Record<string, DatabaseSchemaDataWarehouseTable | DatabaseSchemaViewTable> // databaseTableListLogic
    posthogTablesMap: Record<string, DatabaseSchemaTable> // databaseTableListLogic
    metadata: HogQLMetadataResponse | null // sqlEditorLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface infoTabLogicActions {
    loadUpstream: (modelId: string) => {
        modelId: string
    } // sqlEditorLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface infoTabLogicMeta {
    key: string
}

export type infoTabLogicType = MakeLogicType<
    infoTabLogicValues,
    infoTabLogicActions,
    InfoTabLogicProps,
    infoTabLogicMeta
>

export const infoTabLogic = kea<infoTabLogicType>([
    path(['data-warehouse', 'editor', 'sidebar', 'infoTabLogic']),
    props({} as InfoTabLogicProps),
    key((props) => `${props.tabId}-${props.viewId ?? 'new'}`),
    connect((props: InfoTabLogicProps) => ({
        values: [
            sqlEditorLogic({ tabId: props.tabId }),
            ['metadata'],
            databaseTableListLogic,
            ['posthogTablesMap', 'dataWarehouseTablesMap'],
        ],
        actions: [sqlEditorLogic({ tabId: props.tabId }), ['loadUpstream']],
        logic: props.viewId ? [materializationJobsLogic({ viewId: props.viewId })] : [],
    })),
    afterMount(({ actions, props }) => {
        if (props.viewId) {
            actions.loadUpstream(props.viewId)
        }
    }),
])
