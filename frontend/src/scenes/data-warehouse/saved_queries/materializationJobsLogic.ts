export const materializationJobsLogic = kea<materializationJobsLogicType>([
    path(['scenes', 'data-warehouse', 'saved_queries', 'materializationJobsLogic']),
    props({} as MaterializationJobsLogicProps),
    key((props) => props.viewId),
    connect(() => ({
        actions: [
            dataWarehouseViewsLogic,
            ['updateDataWarehouseSavedQuerySuccess', 'runDataWarehouseSavedQueryFailure'],
        ],
    })),
    actions({
        setStartingMaterialization: (starting: boolean) => ({ starting }),
        resumeMaterialization: true,
        setResumingMaterialization: (resuming: boolean) => ({ resuming }),
        setInitialSyncFrequency: (syncFrequency: DataModelingSyncInterval) => ({ syncFrequency }),
        setIncrementalDraft: (draft: Partial<IncrementalConfigDraft>) => ({ draft }),
        // Distinct from setIncrementalDraft so that reflecting the saved config into the draft
        // doesn't count as the user touching it.
        seedIncrementalDraft: (draft: IncrementalConfigDraft) => ({ draft }),
    }),
    loaders(({ values, props }) => ({
        savedQuery: [
            null as DataWarehouseSavedQuery | null,
            {
                loadSavedQuery: async () => {
                    if (!props.viewId) {
                        return null
                    }
                    return await api.dataWarehouseSavedQueries.get(props.viewId)
                },
            },
        ],
        incrementalCheck: [
            null as DataWarehouseSavedQueryIncrementalCheck | null,
            {
                loadIncrementalCheck: async () => {
                    const sql = values.savedQuery?.query?.query
                    if (!sql) {
                        return null
                    }
                    return await api.dataWarehouseSavedQueries.checkIncremental({ query: sql })
                },
            },
        ],
        dataModelingJobs: [
            null as PaginatedResponse<DataModelingJob> | null,
            {
                loadDataModelingJobs: async () => {
                    return await api.dataWarehouseSavedQueries.dataWarehouseDataModelingJobs.list(
                        props.viewId,
                        values.dataModelingJobs?.results.length
                            ? Math.max(values.dataModelingJobs.results.length, DEFAULT_JOBS_PAGE_SIZE)
                            : DEFAULT_JOBS_PAGE_SIZE,
                        0
                    )
                },
                loadOlderDataModelingJobs: async () => {
                    const nextUrl = values.dataModelingJobs?.next

                    if (!nextUrl) {
                        return values.dataModelingJobs
                    }

                    const res = await api.get<PaginatedResponse<DataModelingJob>>(nextUrl)
                    res.results = [...(values.dataModelingJobs?.results ?? []), ...res.results]

                    return res
                },
            },
        ],
    })),
    reducers({
        // What the not-yet-materialized panel will ask for. Kept here rather than in component state
        // so it survives the panel remounting while the saved query reloads.
        initialSyncFrequency: [
            DEFAULT_MATERIALIZE_SYNC_FREQUENCY,
            {
                setInitialSyncFrequency: (_, { syncFrequency }: { syncFrequency: DataModelingSyncInterval }) =>
                    syncFrequency,
            },
        ],
        incrementalDraft: [
            EMPTY_INCREMENTAL_DRAFT,
            {
                setIncrementalDraft: (
                    state: IncrementalConfigDraft,
                    { draft }: { draft: Partial<IncrementalConfigDraft> }
                ) => ({
                    ...state,
                    ...draft,
                }),
                seedIncrementalDraft: (_: IncrementalConfigDraft, { draft }: { draft: IncrementalConfigDraft }) =>
                    draft,
                // Pre-select the first candidate so enabling incremental starts from a working config.
                loadIncrementalCheckSuccess: (
                    state: IncrementalConfigDraft,
                    { incrementalCheck }: { incrementalCheck: DataWarehouseSavedQueryIncrementalCheck | null }
                ) =>
                    state.incrementalKey
                        ? state
                        : { ...state, incrementalKey: incrementalCheck?.key_candidates[0] ?? null },
            },
        ],
        // Blocks the saved config from overwriting in-progress edits when the saved query repolls.
        incrementalDraftTouched: [
            false,
            {
                setIncrementalDraft: () => true,
            },
        ],
        resumingMaterialization: [
            false,
            {
                resumeMaterialization: () => true,
                setResumingMaterialization: (_, { resuming }: { resuming: boolean }) => resuming,
            },
        ],
        startingMaterialization: [
            false,
            {
                setStartingMaterialization: (_, { starting }: { starting: boolean }) => starting,
                // No job exists when the request itself failed, so the job-status reset below never
                // fires and the controls would stay disabled until the panel remounts.
                runDataWarehouseSavedQueryFailure: () => false,
                loadDataModelingJobsSuccess: (
                    state: boolean,
                    { dataModelingJobs }: { dataModelingJobs: PaginatedResponse<DataModelingJob> | null }
                ) => {
                    const currentJobStatus = dataModelingJobs?.results?.[0]?.status
                    if (
                        currentJobStatus &&
                        ['Running', 'Completed', 'Failed', 'Cancelled', 'Skipped'].includes(currentJobStatus)
                    ) {
                        return false
                    }
                    return state
                },
            },
        ],
    }),
    selectors({
        hasMoreJobsToLoad: [
            (s) => [s.dataModelingJobs],
            (dataModelingJobs: PaginatedResponse<DataModelingJob> | null) => !!dataModelingJobs?.next,
        ],
        lastSuccessfulSyncAt: [
            (s) => [s.dataModelingJobs],
            (dataModelingJobs: PaginatedResponse<DataModelingJob> | null) =>
                latestSuccessfulSyncAt(dataModelingJobs?.results),
        ],
    }),
    afterMount(({ actions, props }) => {
        if (props.viewId) {
            actions.loadDataModelingJobs()
            actions.loadSavedQuery()
        }
    }),
    propsChanged(({ actions, props }, oldProps) => {
        if (props.viewId && props.viewId !== oldProps.viewId) {
            actions.loadDataModelingJobs()
            actions.loadSavedQuery()
        }
    }),
    listeners(({ actions, cache, props, values }) => ({
        resumeMaterialization: async () => {
            try {
                await warehouseSavedQueriesResumeCreate(String(ApiConfig.getCurrentTeamId()), props.viewId)
                lemonToast.success('Materialization resumed. The next scheduled run will include this view.')
                actions.loadSavedQuery()
                actions.loadDataModelingJobs()
            } catch {
                lemonToast.error(
                    "Couldn't resume materialization. Try again, and contact support if it keeps happening."
                )
            } finally {
                actions.setResumingMaterialization(false)
            }
        },
        loadSavedQuerySuccess: ({ savedQuery }) => {
            if (!savedQuery || props.kind === 'endpoint') {
                return
            }
            if (!featureFlagLogic.findMounted()?.values.featureFlags[FEATURE_FLAGS.DATA_MODELING_INCREMENTAL_VIEWS]) {
                return
            }
            // Reflect the saved config so a materialized view's editor starts from what is
            // actually configured, not from the empty draft.
            if (!values.incrementalDraftTouched && savedQuery.incremental?.enabled) {
                actions.seedIncrementalDraft({
                    enabled: true,
                    incrementalKey: savedQuery.incremental.incremental_key,
                    uniqueKey: savedQuery.incremental.unique_key,
                    lookbackSeconds: savedQuery.incremental.lookback_seconds ?? 0,
                })
            }
            // One eligibility check per mount: savedQuery reloads on every jobs poll, and the
            // query text can't change while this panel is open.
            if (cache.incrementalCheckRequested) {
                return
            }
            cache.incrementalCheckRequested = true
            actions.loadIncrementalCheck()
        },
        updateDataWarehouseSavedQuerySuccess: ({ payload }) => {
            // The sync frequency dropdown mutates this saved query through dataWarehouseViewsLogic, which
            // doesn't own our `savedQuery`. Reload it so the displayed frequency reflects the new value
            // immediately instead of reverting until the next poll.
            if (payload?.id === props.viewId) {
                actions.loadSavedQuery()
            }
        },
        loadDataModelingJobsSuccess: () => {
            // Refresh saved query alongside jobs so latest_error / status / sync_frequency stay in sync.
            actions.loadSavedQuery()
            cache.disposables.add(() => {
                const timeoutId = setTimeout(() => {
                    actions.loadDataModelingJobs()
                }, REFRESH_INTERVAL)
                return () => clearTimeout(timeoutId)
            }, 'dataModelingJobsRefreshTimeout')
        },
    })),
])
