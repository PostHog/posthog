export const materializationJobsLogic = kea<materializationJobsLogicType>([
    path(['scenes', 'data-warehouse', 'saved_queries', 'materializationJobsLogic']),
    props({} as MaterializationJobsLogicProps),
    key((props) => props.viewId),
    connect(() => ({
        actions: [
            dataWarehouseViewsLogic,
            [
                'updateDataWarehouseSavedQuery',
                'updateDataWarehouseSavedQuerySuccess',
                'updateDataWarehouseSavedQueryFailed',
                'runDataWarehouseSavedQueryFailure',
                'runDataWarehouseSavedQuerySuccess',
                'materializationChanged',
            ],
        ],
    })),
    actions({
        refreshMaterialization: true,
        scheduleJobsRefresh: (delay: number) => ({ delay }),
        setStartingMaterialization: (starting: boolean) => ({ starting }),
        resumeMaterialization: true,
        setSyncFrequencyDraft: (frequency: SyncFrequencyValue) => ({ frequency }),
        clearSyncFrequencyDraft: true,
        discardMaterializationChanges: true,
        saveMaterializationChanges: true,
        finishSavingMaterialization: true,
        setResumingMaterialization: (resuming: boolean) => ({ resuming }),
        setInitialSyncFrequency: (syncFrequency: DataModelingSyncInterval) => ({ syncFrequency }),
        setIncrementalDraft: (draft: Partial<IncrementalConfigDraft>) => ({ draft }),
        // Distinct from setIncrementalDraft so that reflecting the saved config into the draft
        // doesn't count as the user touching it.
        seedIncrementalDraft: (draft: IncrementalConfigDraft) => ({ draft }),
    }),
    loaders(({ values, props, cache }) => ({
        savedQuery: [
            null as DataWarehouseSavedQuery | null,
            {
                loadSavedQuery: async (_: void, breakpoint) => {
                    if (!props.viewId) {
                        return null
                    }
                    const savedQuery = await api.dataWarehouseSavedQueries.get(props.viewId)
                    breakpoint()
                    return savedQuery
                },
            },
        ],
        incrementalCheck: [
            null as DataWarehouseSavedQueryIncrementalCheck | null,
            {
                loadIncrementalCheck: async () => {
                    const sql = values.savedQuery?.query?.query
                    if (!sql) {
                        return null
                    }
                    // A rejected check is not the user's error, so never toast: the panel just omits the
                    // incremental option. A 4xx is a deterministic refusal, so it is not retried. Anything
                    // else is ours to look at, and the next savedQuery reload gets to try again.
                    try {
                        return await api.dataWarehouseSavedQueries.checkIncremental({ query: sql })
                    } catch (e) {
                        if (!(e instanceof ApiError && e.status && e.status >= 400 && e.status < 500)) {
                            posthog.captureException(e)
                            cache.incrementalCheckRequested = false
                        }
                        return null
                    }
                },
            },
        ],
        dataModelingJobs: [
            null as PaginatedResponse<DataModelingJob> | null,
            {
                loadDataModelingJobs: async (_: void, breakpoint) => {
                    const jobs = await api.dataWarehouseSavedQueries.dataWarehouseDataModelingJobs.list(
                        props.viewId,
                        values.dataModelingJobs?.results.length
                            ? Math.max(values.dataModelingJobs.results.length, DEFAULT_JOBS_PAGE_SIZE)
                            : DEFAULT_JOBS_PAGE_SIZE,
                        0
                    )
                    breakpoint()
                    return jobs
                },
                loadOlderDataModelingJobs: async () => {
                    const nextUrl = values.dataModelingJobs?.next

                    if (!nextUrl) {
                        return values.dataModelingJobs
                    }

                    const res = await api.get<PaginatedResponse<DataModelingJob>>(nextUrl)
                    res.results = [...(values.dataModelingJobs?.results ?? []), ...res.results]

                    return res
                },
            },
        ],
    })),
    reducers({
        savedQueryError: [
            false,
            {
                loadSavedQueryFailure: () => true,
                loadSavedQuerySuccess: () => false,
            },
        ],
        dataModelingJobsError: [
            false,
            {
                loadDataModelingJobsFailure: () => true,
                loadDataModelingJobsSuccess: () => false,
            },
        ],
        savedQueryRefreshPending: [
            false,
            {
                refreshMaterialization: () => true,
                loadSavedQuerySuccess: () => false,
            },
        ],
        jobsRefreshPending: [
            false,
            {
                refreshMaterialization: () => true,
                loadDataModelingJobsSuccess: () => false,
            },
        ],
        syncFrequencyDraft: [
            null as SyncFrequencyValue | null,
            {
                setSyncFrequencyDraft: (_, { frequency }) => frequency,
                clearSyncFrequencyDraft: () => null,
                discardMaterializationChanges: () => null,
            },
        ],
        savingMaterialization: [
            false,
            {
                saveMaterializationChanges: () => true,
                finishSavingMaterialization: () => false,
            },
        ],
        // What the not-yet-materialized panel will ask for. Kept here rather than in component state
        // so it survives the panel remounting while the saved query reloads.
        initialSyncFrequency: [
            DEFAULT_MATERIALIZE_SYNC_FREQUENCY,
            {
                setInitialSyncFrequency: (_, { syncFrequency }: { syncFrequency: DataModelingSyncInterval }) =>
                    syncFrequency,
            },
        ],
        incrementalDraft: [
            EMPTY_INCREMENTAL_DRAFT,
            {
                setIncrementalDraft: (
                    state: IncrementalConfigDraft,
                    { draft }: { draft: Partial<IncrementalConfigDraft> }
                ) => ({
                    ...state,
                    ...draft,
                }),
                seedIncrementalDraft: (_: IncrementalConfigDraft, { draft }: { draft: IncrementalConfigDraft }) =>
                    draft,
                // Pre-select the first candidate so enabling incremental starts from a working config.
                loadIncrementalCheckSuccess: (
                    state: IncrementalConfigDraft,
                    { incrementalCheck }: { incrementalCheck: DataWarehouseSavedQueryIncrementalCheck | null }
                ) =>
                    state.incrementalKey
                        ? state
                        : { ...state, incrementalKey: incrementalCheck?.key_candidates[0] ?? null },
            },
        ],
        // Blocks the saved config from overwriting in-progress edits when the saved query repolls.
        incrementalDraftTouched: [
            false,
            {
                setIncrementalDraft: () => true,
                discardMaterializationChanges: () => false,
            },
        ],
        resumingMaterialization: [
            false,
            {
                resumeMaterialization: () => true,
                setResumingMaterialization: (_, { resuming }: { resuming: boolean }) => resuming,
            },
        ],
        startingMaterialization: [
            false,
            {
                setStartingMaterialization: (_, { starting }: { starting: boolean }) => starting,
                // No job exists when the request itself failed, so the job-status reset below never
                // fires and the controls would stay disabled until the panel remounts.
                runDataWarehouseSavedQueryFailure: () => false,
                loadDataModelingJobsSuccess: (
                    state: boolean,
                    { dataModelingJobs }: { dataModelingJobs: PaginatedResponse<DataModelingJob> | null }
                ) => {
                    const currentJobStatus = dataModelingJobs?.results?.[0]?.status
                    if (
                        currentJobStatus &&
                        ['Running', 'Completed', 'Failed', 'Cancelled', 'Skipped'].includes(currentJobStatus)
                    ) {
                        return false
                    }
                    return state
                },
            },
        ],
    }),
    selectors({
        materializationRefreshPending: [
            (s) => [s.savedQueryRefreshPending, s.jobsRefreshPending],
            (savedQueryPending: boolean, jobsPending: boolean): boolean => savedQueryPending || jobsPending,
        ],
        refreshModeChanged: [
            (s) => [s.savedQuery, s.incrementalDraft, s.incrementalDraftTouched],
            (savedQuery: DataWarehouseSavedQuery | null, draft: IncrementalConfigDraft, touched: boolean): boolean => {
                const saved = savedQuery?.incremental
                return (
                    touched &&
                    !!savedQuery &&
                    (draft.enabled !== !!saved?.enabled ||
                        (!!saved?.enabled &&
                            draft.enabled &&
                            (draft.incrementalKey !== saved.incremental_key ||
                                [...draft.uniqueKey].sort().join(',') !== [...saved.unique_key].sort().join(',') ||
                                draft.lookbackSeconds !== (saved.lookback_seconds ?? 0))))
                )
            },
        ],
        hasMaterializationChanges: [
            (s) => [s.savedQuery, s.syncFrequencyDraft, s.refreshModeChanged],
            (
                savedQuery: DataWarehouseSavedQuery | null,
                frequency: SyncFrequencyValue | null,
                modeChanged: boolean
            ): boolean =>
                !!savedQuery?.is_materialized &&
                (modeChanged || (frequency !== null && frequency !== (savedQuery.sync_frequency || 'never'))),
        ],
        hasMoreJobsToLoad: [
            (s) => [s.dataModelingJobs],
            (dataModelingJobs: PaginatedResponse<DataModelingJob> | null) => !!dataModelingJobs?.next,
        ],
        lastSuccessfulSyncAt: [
            (s) => [s.dataModelingJobs],
            (dataModelingJobs: PaginatedResponse<DataModelingJob> | null) =>
                latestSuccessfulSyncAt(dataModelingJobs?.results),
        ],
    }),
    afterMount(({ actions, props }) => {
        if (props.viewId) {
            actions.loadDataModelingJobs()
            actions.loadSavedQuery()
        }
    }),
    propsChanged(({ actions, props }, oldProps) => {
        if (props.viewId && props.viewId !== oldProps.viewId) {
            actions.loadDataModelingJobs()
            actions.loadSavedQuery()
        }
    }),
    listeners(({ actions, cache, props, values }) => ({
        materializationChanged: ({ viewId }) => {
            if (viewId === props.viewId) {
                actions.refreshMaterialization()
            }
        },
        runDataWarehouseSavedQuerySuccess: ({ viewId }) => {
            if (viewId === props.viewId) {
                actions.refreshMaterialization()
            }
        },
        refreshMaterialization: () => {
            actions.loadSavedQuery()
            actions.loadDataModelingJobs()
        },
        loadDataModelingJobs: () => {
            cache.disposables.dispose('dataModelingJobsRefreshTimeout')
        },
        scheduleJobsRefresh: ({ delay }) => {
            cache.disposables.add(() => {
                const timeoutId = setTimeout(() => actions.loadDataModelingJobs(), delay)
                return () => clearTimeout(timeoutId)
            }, 'dataModelingJobsRefreshTimeout')
        },
        loadDataModelingJobsFailure: () => {
            actions.scheduleJobsRefresh(IDLE_REFRESH_INTERVAL_MS)
        },
        setSyncFrequencyDraft: ({ frequency }) => {
            // The cadence bar reports a change on every click, including the segment that is already
            // selected, so a draft can hold the cadence that is already saved. Such a draft is invisible
            // because it is not a change, until something else moves the saved cadence. Pausing sets the
            // saved cadence to 'never', which makes the stale draft look like an edit, and saving it
            // resumes the schedule the user just paused.
            if (frequency === (values.savedQuery?.sync_frequency || 'never')) {
                actions.clearSyncFrequencyDraft()
            }
        },
        discardMaterializationChanges: () => {
            const saved = values.savedQuery?.incremental
            actions.seedIncrementalDraft(
                saved?.enabled
                    ? {
                          enabled: true,
                          incrementalKey: saved.incremental_key,
                          uniqueKey: saved.unique_key,
                          lookbackSeconds: saved.lookback_seconds ?? 0,
                      }
                    : { ...EMPTY_INCREMENTAL_DRAFT, incrementalKey: values.incrementalCheck?.key_candidates[0] ?? null }
            )
        },
        saveMaterializationChanges: () => {
            const draft = values.incrementalDraft
            if (!values.savedQuery || !values.hasMaterializationChanges) {
                actions.finishSavingMaterialization()
                return
            }
            actions.updateDataWarehouseSavedQuery({
                id: props.viewId,
                ...(values.syncFrequencyDraft !== null ? { sync_frequency: values.syncFrequencyDraft } : {}),
                ...(values.refreshModeChanged
                    ? {
                          incremental:
                              draft.enabled && draft.incrementalKey
                                  ? {
                                        enabled: true,
                                        incremental_key: draft.incrementalKey,
                                        unique_key: draft.uniqueKey,
                                        lookback_seconds: draft.lookbackSeconds,
                                    }
                                  : null,
                      }
                    : {}),
                types: [[]],
                lifecycle: 'update',
            })
        },
        updateDataWarehouseSavedQueryFailed: ({ viewId }) => {
            if (viewId === props.viewId) {
                actions.finishSavingMaterialization()
            }
        },
        resumeMaterialization: async () => {
            try {
                await warehouseSavedQueriesResumeCreate(String(ApiConfig.getCurrentTeamId()), props.viewId)
                lemonToast.success('Materialization resumed. The next scheduled run will include this view.')
                actions.loadSavedQuery()
                actions.loadDataModelingJobs()
            } catch {
                lemonToast.error(
                    "Couldn't resume materialization. Try again, and contact support if it keeps happening."
                )
            } finally {
                actions.setResumingMaterialization(false)
            }
        },
        loadSavedQuerySuccess: ({ savedQuery }) => {
            if (!savedQuery || props.kind === 'endpoint') {
                return
            }
            if (!featureFlagLogic.findMounted()?.values.featureFlags[FEATURE_FLAGS.DATA_MODELING_INCREMENTAL_VIEWS]) {
                return
            }
            // Reflect the saved config so a materialized view's editor starts from what is
            // actually configured, not from the empty draft.
            if (!values.incrementalDraftTouched && savedQuery.incremental?.enabled) {
                actions.seedIncrementalDraft({
                    enabled: true,
                    incrementalKey: savedQuery.incremental.incremental_key,
                    uniqueKey: savedQuery.incremental.unique_key,
                    lookbackSeconds: savedQuery.incremental.lookback_seconds ?? 0,
                })
            }
            // One eligibility check per mount: savedQuery reloads on every jobs poll, and the
            // query text can't change while this panel is open.
            if (cache.incrementalCheckRequested) {
                return
            }
            cache.incrementalCheckRequested = true
            actions.loadIncrementalCheck()
        },
        updateDataWarehouseSavedQuerySuccess: ({ payload }) => {
            // The sync frequency dropdown mutates this saved query through dataWarehouseViewsLogic, which
            // doesn't own our `savedQuery`. Reload it so the displayed frequency reflects the new value
            // immediately instead of reverting until the next poll.
            if (payload?.id === props.viewId) {
                if (values.savingMaterialization && values.savedQuery) {
                    actions.loadSavedQuerySuccess({ ...values.savedQuery, ...payload } as DataWarehouseSavedQuery)
                    actions.discardMaterializationChanges()
                    actions.finishSavingMaterialization()
                }
                actions.loadSavedQuery()
            }
        },
        loadDataModelingJobsSuccess: () => {
            // Refresh saved query alongside jobs so latest_error / status / sync_frequency stay in sync.
            actions.loadSavedQuery()
            const active = values.startingMaterialization || values.dataModelingJobs?.results[0]?.status === 'Running'
            actions.scheduleJobsRefresh(active ? ACTIVE_REFRESH_INTERVAL_MS : IDLE_REFRESH_INTERVAL_MS)
        },
    })),
])
