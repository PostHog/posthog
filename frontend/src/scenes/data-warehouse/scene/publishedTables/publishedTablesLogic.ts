function getErrorMessage(error: unknown, fallback: string): string {
    if (typeof error === 'object' && error !== null) {
        const detail = 'detail' in error ? error.detail : undefined
        if (typeof detail === 'string') {
            return detail
        }
    }
    return fallback
}

