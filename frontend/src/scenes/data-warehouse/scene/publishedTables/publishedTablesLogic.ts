export const publishedTablesLogic = kea<publishedTablesLogicType>([
    path(['scenes', 'data-warehouse', 'scene', 'publishedTables', 'publishedTablesLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        openPublishModal: true,
        closePublishModal: true,
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
    }),
    reducers({
        publishModalOpen: [
            false,
            {
                openPublishModal: () => true,
                closePublishModal: () => false,
            },
        ],
        searchTerm: [
            '',
            {
                setSearchTerm: (_, { searchTerm }) => searchTerm,
            },
        ],
        modeledTablesError: [
            null as string | null,
            {
                loadModeledTables: () => null,
                loadModeledTablesSuccess: () => null,
                loadModeledTablesFailure: () => 'Could not load modeled tables. Try again.',
            },
        ],
        publishedTablesError: [
            null as string | null,
            {
                loadPublishedTables: () => null,
                loadPublishedTablesSuccess: () => null,
                loadPublishedTablesFailure: () => 'Could not load published tables. Try again.',
            },
        ],
    }),
    loaders(({ values }) => ({
        publishedTables: [
            [] as PublishedTableApi[],
            {
                loadPublishedTables: async (): Promise<PublishedTableApi[]> => {
                    const response = await dataWarehouseApi.dataWarehouseManagedWarehousePublishedTablesRetrieve(
                        String(values.currentTeamId)
                    )
                    return response.results
                },
            },
        ],
        modeledTables: [
            [] as ModeledTableApi[],
            {
                loadModeledTables: async (): Promise<ModeledTableApi[]> => {
                    const response = await dataWarehouseApi.dataWarehouseManagedWarehouseModeledTablesRetrieve(
                        String(values.currentTeamId)
                    )
                    return response.results
                },
            },
        ],
        republishedTable: [
            null as PublishedTableApi | null,
            {
                republishTable: async (id: string): Promise<PublishedTableApi> =>
                    await dataWarehouseApi.dataWarehouseManagedWarehouseRepublishTableCreate(
                        String(values.currentTeamId),
                        { id }
                    ),
            },
        ],
        unpublishedTableId: [
            null as string | null,
            {
                unpublishTable: async (id: string): Promise<string> => {
                    await dataWarehouseApi.dataWarehouseManagedWarehousePublishedTableDestroy(
                        String(values.currentTeamId),
                        { id }
                    )
                    return id
                },
            },
        ],
    })),
    forms(({ actions, values }) => ({
        publishTable: {
            defaults: {
                sourceTableKey: '',
                name: '',
            } as PublishTableFormValues,
            errors: ({ sourceTableKey }: PublishTableFormValues) => ({
                sourceTableKey: sourceTableKey ? undefined : 'Select a modeled table',
            }),
            submit: async ({ sourceTableKey, name }: PublishTableFormValues): Promise<void> => {
                const sourceTable = values.modeledTables.find(
                    (table: ModeledTableApi) => `${table.schema_name}.${table.table_name}` === sourceTableKey
                )
                if (!sourceTable) {
                    throw new Error('The selected modeled table is no longer available.')
                }

                try {
                    await dataWarehouseApi.dataWarehouseManagedWarehousePublishTableCreate(
                        String(values.currentTeamId),
                        {
                            source_schema_name: sourceTable.schema_name,
                            source_table_name: sourceTable.table_name,
                            ...(name.trim() ? { name: name.trim() } : {}),
                        }
                    )
                    lemonToast.success('Table queued for publishing')
                    actions.closePublishModal()
                    actions.resetPublishTable()
                    actions.loadPublishedTables()
                } catch (error) {
                    lemonToast.error(getErrorMessage(error, 'Could not publish the table. Try again.'))
                    throw error
                }
            },
        },
    })),
    selectors({
        filteredPublishedTables: [
            (selectors) => [selectors.publishedTables, selectors.searchTerm],
            (publishedTables: PublishedTableApi[], searchTerm: string): PublishedTableApi[] => {
                const normalizedSearchTerm = searchTerm.trim().toLowerCase()
                if (!normalizedSearchTerm) {
                    return publishedTables
                }
                return publishedTables.filter((publication) =>
                    [publication.name, publication.source_schema_name, publication.source_table_name].some((value) =>
                        value.toLowerCase().includes(normalizedSearchTerm)
                    )
                )
            },
        ],
        hasActivePublications: [
            (selectors) => [selectors.publishedTables],
            (publishedTables: PublishedTableApi[]): boolean =>
                publishedTables.some((publication) => ACTIVE_STATUSES.has(publication.status)),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openPublishModal: () => {
            actions.loadModeledTables()
        },
        closePublishModal: () => {
            actions.resetPublishTable()
        },
        loadPublishedTablesSuccess: () => {
            cache.disposables.add(() => {
                if (!values.hasActivePublications || document.hidden) {
                    return
                }
                const timeoutId = window.setTimeout(() => actions.loadPublishedTables(), POLL_INTERVAL_MS)
                return () => window.clearTimeout(timeoutId)
            }, 'publishedTablesPoll')
        },
        loadPublishedTablesFailure: () => {
            cache.disposables.add(() => {
                if (!values.hasActivePublications || document.hidden) {
                    return
                }
                const timeoutId = window.setTimeout(() => actions.loadPublishedTables(), POLL_INTERVAL_MS)
                return () => window.clearTimeout(timeoutId)
            }, 'publishedTablesPoll')
        },
        republishTableSuccess: () => {
            lemonToast.success('Table queued for publishing')
            actions.loadPublishedTables()
        },
        republishTableFailure: ({ errorObject }) => {
            lemonToast.error(getErrorMessage(errorObject, 'Could not republish the table. Try again.'))
        },
        unpublishTableSuccess: () => {
            lemonToast.success('Table unpublished')
            actions.loadPublishedTables()
        },
        unpublishTableFailure: ({ errorObject }) => {
            lemonToast.error(getErrorMessage(errorObject, 'Could not unpublish the table. Try again.'))
        },
    })),
    afterMount(({ actions, values, cache }) => {
        actions.loadPublishedTables()
        cache.disposables.add(() => {
            const handleVisibilityChange = (): void => {
                if (!document.hidden && values.hasActivePublications) {
                    actions.loadPublishedTables()
                }
            }
            document.addEventListener('visibilitychange', handleVisibilityChange)
            return () => document.removeEventListener('visibilitychange', handleVisibilityChange)
        }, 'publishedTablesVisibility')
    }),
])
