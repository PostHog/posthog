import { loaders } from 'kea-loaders'
import { subscriptions } from 'kea-subscriptions'

import { teamLogic } from 'scenes/teamLogic'

import {
    dataWarehouseManagedWarehouseMonitoringRetrieve,
    dataWarehouseManagedWarehouseMonitoringTimeseriesRetrieve,
} from 'products/data_warehouse/frontend/generated/api'
import type {
    DataWarehouseManagedWarehouseMonitoringTimeseriesRetrieveParams,
    ManagedWarehouseMonitoringSeriesResponseApi,
    ManagedWarehouseMonitoringSnapshotResponseApi,
} from 'products/data_warehouse/frontend/generated/api.schemas'

const ACTIVE_REFRESH_INTERVAL_MS = 15_000
const STABLE_REFRESH_INTERVAL_MS = 60_000
const SERIES_REFRESH_INTERVAL_MS = 60_000

export type MonitoringWindow = NonNullable<DataWarehouseManagedWarehouseMonitoringTimeseriesRetrieveParams['window']>
export type MonitoringMetric = NonNullable<DataWarehouseManagedWarehouseMonitoringTimeseriesRetrieveParams['metric']>
export type MonitoringWorker = ManagedWarehouseMonitoringSnapshotResponseApi['workers'][number]

export const MONITORING_WINDOW_OPTIONS: { label: string; value: MonitoringWindow }[] = [
    { label: '1h', value: '1h' },
    { label: '6h', value: '6h' },
    { label: '24h', value: '24h' },
    { label: '7d', value: '7d' },
    { label: '30d', value: '30d' },
]

const MONITORING_METRICS: MonitoringMetric[] = [
    'query_rate',
    'error_ratio',
    'duration_p50',
    'duration_p95',
    'sessions_active',
    'acquire_p95',
    'storage_bytes',
    'worker_crash_rate',
]

const WORKER_STATE_SEVERITY: Record<string, number> = {
    lost: 0,
    draining: 1,
    spawning: 2,
    activating: 3,
    reserved: 4,
    hot: 5,
    hot_idle: 6,
    idle: 7,
}

function workerSeverity(worker: MonitoringWorker): number {
    if (worker.session?.stalled) {
        return -1
    }
    return WORKER_STATE_SEVERITY[worker.state] ?? 100
}

