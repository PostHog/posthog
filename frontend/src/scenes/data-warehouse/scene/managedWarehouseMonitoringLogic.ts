export const managedWarehouseMonitoringLogic = kea<managedWarehouseMonitoringLogicType>([
    path(['scenes', 'data-warehouse', 'scene', 'managedWarehouseMonitoringLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        refreshMonitoring: true,
        resetMonitoringData: true,
        setMonitoringSeriesError: (hasError: boolean) => ({ hasError }),
        setMonitoringSnapshotError: (hasError: boolean) => ({ hasError }),
        setMonitoringWindow: (monitoringWindow: MonitoringWindow) => ({ monitoringWindow }),
    }),
    loaders(({ values, actions }) => ({
        monitoringSnapshot: [
            null as ManagedWarehouseMonitoringSnapshotResponseApi | null,
            {
                loadMonitoringSnapshot: async (_: void, breakpoint) => {
                    const requestedTeamId = values.currentTeamId
                    if (!requestedTeamId) {
                        return null
                    }
                    let response: ManagedWarehouseMonitoringSnapshotResponseApi
                    try {
                        response = await dataWarehouseManagedWarehouseMonitoringRetrieve(String(requestedTeamId))
                    } catch (error) {
                        breakpoint()
                        throw error
                    }
                    breakpoint()
                    return response
                },
            },
        ],
        monitoringSeries: [
            [] as ManagedWarehouseMonitoringSeriesResponseApi[],
            {
                loadMonitoringSeries: async (requestedWindow: MonitoringWindow | undefined, breakpoint) => {
                    const requestedTeamId = values.currentTeamId
                    if (!requestedTeamId) {
                        return []
                    }
                    const monitoringWindow = requestedWindow ?? values.monitoringWindow
                    const results = await Promise.allSettled(
                        MONITORING_METRICS.map((metric) =>
                            dataWarehouseManagedWarehouseMonitoringTimeseriesRetrieve(String(requestedTeamId), {
                                metric,
                                window: monitoringWindow,
                            })
                        )
                    )
                    breakpoint()

                    const successfulResponses = results.flatMap((result) =>
                        result.status === 'fulfilled' ? [result.value] : []
                    )
                    if (!successfulResponses.length) {
                        const firstFailure = results.find((result) => result.status === 'rejected')
                        throw firstFailure?.reason ?? new Error('No warehouse monitoring metrics were returned')
                    }

                    const previousResponses =
                        values.monitoringSeriesWindow === monitoringWindow ? values.monitoringSeries : []
                    const responsesByMetric = new Map(previousResponses.map((response) => [response.metric, response]))
                    for (const response of successfulResponses) {
                        responsesByMetric.set(response.metric, response)
                    }
                    actions.setMonitoringSeriesError(successfulResponses.length !== results.length)

                    return MONITORING_METRICS.flatMap((metric) => {
                        const response = responsesByMetric.get(metric)
                        return response ? [response] : []
                    })
                },
            },
        ],
    })),
    reducers({
        monitoringWindow: [
            '24h' as MonitoringWindow,
            {
                setMonitoringWindow: (_, { monitoringWindow }) => monitoringWindow,
            },
        ],
        monitoringSnapshot: {
            resetMonitoringData: () => null,
        },
        monitoringSeries: {
            resetMonitoringData: () => [],
        },
        monitoringSeriesResolved: [
            false,
            {
                loadMonitoringSeriesSuccess: () => true,
                loadMonitoringSeriesFailure: () => true,
                resetMonitoringData: () => false,
            },
        ],
        monitoringSeriesWindow: [
            null as MonitoringWindow | null,
            {
                loadMonitoringSeriesSuccess: (state, { payload }) => payload ?? state,
                resetMonitoringData: () => null,
            },
        ],
        monitoringSnapshotError: [
            false,
            {
                loadMonitoringSnapshot: () => false,
                setMonitoringSnapshotError: (_, { hasError }) => hasError,
                resetMonitoringData: () => false,
            },
        ],
        monitoringSeriesError: [
            false,
            {
                setMonitoringSeriesError: (_, { hasError }) => hasError,
                resetMonitoringData: () => false,
            },
        ],
    }),
    selectors({
        initialMonitoringSeriesLoading: [
            (s) => [s.monitoringSeriesLoading, s.monitoringSeriesResolved, s.monitoringSeriesError],
            (
                monitoringSeriesLoading: boolean,
                monitoringSeriesResolved: boolean,
                monitoringSeriesError: boolean
            ): boolean => monitoringSeriesLoading && !monitoringSeriesResolved && !monitoringSeriesError,
        ],
        hasLiveActivity: [
            (s) => [s.monitoringSnapshot],
            (monitoringSnapshot: ManagedWarehouseMonitoringSnapshotResponseApi | null): boolean =>
                !!monitoringSnapshot &&
                (monitoringSnapshot.totals.running_queries > 0 || monitoringSnapshot.totals.queued_connections > 0),
        ],
        sortedWorkers: [
            (s) => [s.monitoringSnapshot],
            (monitoringSnapshot: ManagedWarehouseMonitoringSnapshotResponseApi | null): MonitoringWorker[] =>
                [...(monitoringSnapshot?.workers ?? [])].sort((a, b) => workerSeverity(a) - workerSeverity(b)),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        refreshMonitoring: () => {
            if (!values.monitoringSnapshotLoading) {
                actions.loadMonitoringSnapshot()
            }
            if (!values.monitoringSeriesLoading) {
                actions.loadMonitoringSeries(values.monitoringWindow)
            }
        },
        setMonitoringWindow: ({ monitoringWindow }) => {
            actions.loadMonitoringSeries(monitoringWindow)
        },
        loadMonitoringSnapshotSuccess: () => {
            if (!values.currentTeamId) {
                return
            }
            actions.setMonitoringSnapshotError(false)
            cache.disposables.add(() => {
                const timeoutId = window.setTimeout(
                    () => {
                        if (!values.monitoringSnapshotLoading) {
                            actions.loadMonitoringSnapshot()
                        }
                    },
                    values.hasLiveActivity ? ACTIVE_REFRESH_INTERVAL_MS : STABLE_REFRESH_INTERVAL_MS
                )
                return () => window.clearTimeout(timeoutId)
            }, 'monitoringSnapshotPoll')
        },
        loadMonitoringSnapshotFailure: () => {
            actions.setMonitoringSnapshotError(true)
            cache.disposables.add(() => {
                const timeoutId = window.setTimeout(() => {
                    if (!values.monitoringSnapshotLoading) {
                        actions.loadMonitoringSnapshot()
                    }
                }, STABLE_REFRESH_INTERVAL_MS)
                return () => window.clearTimeout(timeoutId)
            }, 'monitoringSnapshotPoll')
        },
        loadMonitoringSeriesSuccess: () => {
            if (!values.currentTeamId) {
                return
            }
            cache.disposables.add(() => {
                const timeoutId = window.setTimeout(() => {
                    if (!values.monitoringSeriesLoading) {
                        actions.loadMonitoringSeries(values.monitoringWindow)
                    }
                }, SERIES_REFRESH_INTERVAL_MS)
                return () => window.clearTimeout(timeoutId)
            }, 'monitoringSeriesPoll')
        },
        loadMonitoringSeriesFailure: () => {
            actions.setMonitoringSeriesError(true)
            cache.disposables.add(() => {
                const timeoutId = window.setTimeout(() => {
                    if (!values.monitoringSeriesLoading) {
                        actions.loadMonitoringSeries(values.monitoringWindow)
                    }
                }, SERIES_REFRESH_INTERVAL_MS)
                return () => window.clearTimeout(timeoutId)
            }, 'monitoringSeriesPoll')
        },
    })),
    subscriptions(({ actions, values, cache }) => ({
        currentTeamId: (teamId: number | null, previousTeamId: number | null | undefined) => {
            if (previousTeamId !== undefined && teamId !== previousTeamId) {
                cache.disposables.dispose('monitoringSnapshotPoll')
                cache.disposables.dispose('monitoringSeriesPoll')
                actions.resetMonitoringData()
                actions.loadMonitoringSnapshot()
                actions.loadMonitoringSeries(values.monitoringWindow)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.refreshMonitoring()
    }),
])
