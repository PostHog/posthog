export type expressionModalLogicType = MakeLogicType<
    expressionModalLogicValues,
    expressionModalLogicActions,
    Record<string, any>,
    expressionModalLogicMeta
>

export const expressionModalLogic = kea<expressionModalLogicType>([
    path(['scenes', 'data-warehouse', 'expressionModalLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], databaseTableListLogic, ['connectionId', 'allTablesMap']],
        actions: [databaseTableListLogic, ['loadDatabase']],
    })),
    actions({
        openNewExpressionModal: (tableName: string) => ({ tableName }),
        openEditExpressionModal: (expression: DataWarehouseExpressionApi) => ({ expression }),
        closeExpressionModal: true,
        deleteExpression: (expression: DataWarehouseExpressionApi) => ({ expression }),
        setError: (error: string | null) => ({ error }),
    }),
    loaders(({ values }) => ({
        expressions: [
            [] as DataWarehouseExpressionApi[],
            {
                loadExpressions: async () => {
                    const response = await warehouseExpressionsList(String(values.currentTeamId))
                    return response.results
                },
            },
        ],
    })),
    forms(({ actions, values }) => ({
        expressionForm: {
            defaults: NEW_EXPRESSION,
            errors: ({ field_name, expression }) => ({
                field_name: !field_name
                    ? 'Enter a field name'
                    : !FIELD_NAME_REGEX.test(field_name)
                      ? "Use only letters, numbers, underscores and $. The name can't start with a number."
                      : undefined,
                expression: !expression ? 'Enter an expression' : undefined,
            }),
            submit: async ({ field_name, expression }) => {
                if (!values.selectedTableName) {
                    return
                }
                try {
                    if (values.expressionToEdit) {
                        await warehouseExpressionsPartialUpdate(
                            String(values.currentTeamId),
                            values.expressionToEdit.id,
                            { field_name, expression }
                        )
                        lemonToast.success('Expression updated')
                    } else {
                        await warehouseExpressionsCreate(String(values.currentTeamId), {
                            table_name: values.selectedTableName,
                            field_name,
                            expression,
                            connection_id: values.activeConnectionId,
                        })
                        lemonToast.success('Expression created')
                    }
                    actions.closeExpressionModal()
                    actions.loadExpressions()
                    actions.loadDatabase()
                } catch (error: any) {
                    actions.setError(error.detail ?? "Couldn't save the expression. Check it and try again.")
                    throw error
                }
            },
        },
    })),
    reducers({
        isExpressionModalOpen: [
            false,
            {
                openNewExpressionModal: () => true,
                openEditExpressionModal: () => true,
                closeExpressionModal: () => false,
            },
        ],
        expressionToEdit: [
            null as DataWarehouseExpressionApi | null,
            {
                openNewExpressionModal: () => null,
                openEditExpressionModal: (_, { expression }) => expression,
                closeExpressionModal: () => null,
            },
        ],
        selectedTableName: [
            null as string | null,
            {
                openNewExpressionModal: (_, { tableName }) => tableName,
                openEditExpressionModal: (_, { expression }) => expression.table_name,
                closeExpressionModal: () => null,
            },
        ],
        error: [
            null as string | null,
            {
                openNewExpressionModal: () => null,
                openEditExpressionModal: () => null,
                closeExpressionModal: () => null,
                setError: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        activeConnectionId: [
            (s) => [s.connectionId],
            (connectionId: string | null): string | null =>
                connectionId && connectionId !== POSTHOG_WAREHOUSE ? connectionId : null,
        ],
        expressionSourceQuery: [
            (s) => [s.selectedTableName, s.activeConnectionId],
            (selectedTableName: string | null, activeConnectionId: string | null): HogQLQuery | undefined =>
                selectedTableName
                    ? {
                          kind: NodeKind.HogQLQuery,
                          query: `SELECT * FROM ${selectedTableName}`,
                          connectionId: activeConnectionId ?? undefined,
                      }
                    : undefined,
        ],
        // Reflects the database loaded for the active connection: a direct connection's
        // database contains no posthog-type tables, so the shadowing notice stays hidden there.
        isPostHogTable: [
            (s) => [s.selectedTableName, s.allTablesMap],
            (selectedTableName: string | null, allTablesMap: Record<string, DatabaseSchemaTable>): boolean => {
                const tableType = selectedTableName ? allTablesMap[selectedTableName]?.type : undefined
                return tableType === 'posthog' || tableType === 'system'
            },
        ],
        // Only expressions scoped to the active connection (null scope means the default warehouse)
        expressionsByFieldName: [
            (s) => [s.expressions, s.activeConnectionId],
            (
                expressions: DataWarehouseExpressionApi[],
                activeConnectionId: string | null
            ): Record<string, DataWarehouseExpressionApi> =>
                Object.fromEntries(
                    expressions
                        .filter((expression) => (expression.connection_id ?? null) === activeConnectionId)
                        .map((expression) => [`${expression.table_name}.${expression.field_name}`, expression])
                ),
        ],
    }),
    listeners(({ actions, values }) => ({
        openNewExpressionModal: () => {
            actions.resetExpressionForm()
        },
        openEditExpressionModal: ({ expression }) => {
            actions.resetExpressionForm({
                field_name: expression.field_name,
                expression: expression.expression,
            })
        },
        deleteExpression: ({ expression }) => {
            void deleteWithUndo({
                endpoint: `projects/${values.currentTeamId}/warehouse_expressions`,
                object: { ...expression, name: `${expression.field_name} on ${expression.table_name}` },
                callback: () => {
                    actions.loadExpressions()
                    actions.loadDatabase()
                },
            })
        },
    })),
    afterMount(({ actions }) => {
        actions.loadExpressions()
    }),
])
