export type confirmOrganizationLogicType = MakeLogicType<
    confirmOrganizationLogicValues,
    confirmOrganizationLogicActions
>

export const confirmOrganizationLogic = kea<confirmOrganizationLogicType>([
    path(['scenes', 'organization', 'confirmOrganizationLogic']),

    actions({
        setEmail: (email: string) => ({
            email,
        }),
        setPendingInvite: (pendingInvite: PendingInvite | null) => ({ pendingInvite }),
        signInWithDifferentAccount: true,
    }),

    reducers({
        email: [
            '',
            {
                setEmail: (_, { email }) => email,
            },
        ],
        pendingInvite: [
            null as PendingInvite | null,
            {
                setPendingInvite: (_, { pendingInvite }) => pendingInvite,
            },
        ],
    }),

    forms(() => ({
        confirmOrganization: {
            defaults: {} as ConfirmOrganizationFormValues,
            errors: ({ organization_name, first_name }) => ({
                first_name: !first_name ? 'Please enter your name' : undefined,
                organization_name: !organization_name ? 'Please enter your organization name' : undefined,
            }),

            submit: async (formValues) => {
                await api
                    .create('api/social_signup/', {
                        ...formValues,
                    })
                    .then(() => {
                        // pinned: analytics event name — renaming breaks dashboards
                        posthog.capture('organization creation confirmation completed')
                        const nextUrl = getRelativeNextPath(new URLSearchParams(location.search).get('next'), location)

                        // this url is validated in getRelativeNextPath as either being relative or on the same origin
                        // nosemgrep: javascript.browser.security.open-redirect.js-open-redirect
                        location.href = nextUrl || '/'
                    })
                    .catch((error: any) => {
                        console.error('error', error)
                        lemonToast.error(error.detail || 'Failed to create organization')
                    })
            },
        },
    })),

    listeners(({ actions }) => ({
        setEmail: async ({ email }) => {
            if (!email) {
                return
            }
            // The social login reaches this page without checking whether the email already
            // has an account or a waiting invite. Ask precheck so we can steer a misrouted
            // user away from creating a duplicate organization.
            // null means precheck never answered. Only a successful response sets true/false, so a
            // swallowed failure is not recorded as "no pending invite".
            let hasPendingInvite: boolean | null = null
            try {
                const response = await api.create<SignupEmailPrecheckResponse>('api/signup/precheck', { email })
                hasPendingInvite = !!response.pending_invite
                if (response.pending_invite) {
                    actions.setPendingInvite(response.pending_invite)
                }
            } catch {
                // precheck is best-effort. A failure must never block organization creation.
            }
            // pinned: analytics event name — renaming breaks dashboards
            posthog.capture('organization creation confirmation shown', { has_pending_invite: hasPendingInvite })
        },
        signInWithDifferentAccount: () => {
            // pinned: analytics event name — renaming breaks dashboards
            posthog.capture('organization creation confirmation different account clicked')
            location.href = '/login'
        },
    })),

    urlToAction(({ actions }) => ({
        '/organization/confirm-creation': (_, { email, organization_name, first_name }) => {
            actions.setConfirmOrganizationValues({ organization_name, first_name })
            actions.setEmail(email)
        },
    })),
])
