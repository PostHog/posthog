export type studentProgramLogicType = MakeLogicType<
    studentProgramLogicValues,
    studentProgramLogicActions,
    Record<string, any>,
    studentProgramLogicMeta
>

export const studentProgramLogic = kea<studentProgramLogicType>([
    path(['scenes', 'students', 'studentProgramLogic']),
    connect(() => ({
        values: [
            organizationLogic,
            ['currentOrganization', 'currentOrganizationId', 'isAdminOrOwner'],
            billingLogic,
            ['billing'],
        ],
    })),
    actions({
        setFormSubmitted: (submitted: boolean) => ({ submitted }),
    }),
    reducers({
        formSubmitted: [
            false,
            {
                setFormSubmitted: (_, { submitted }) => submitted,
            },
        ],
    }),
    selectors({
        isCurrentlyOnProgram: [
            (s) => [s.billing],
            (billing: BillingType | null) => {
                return !!billing?.startup_program_label
            },
        ],
        currentProgramLabel: [
            (s) => [s.billing],
            (billing: BillingType | null) => {
                return billing?.startup_program_label || null
            },
        ],
        wasPreviouslyOnProgram: [
            (s) => [s.billing],
            (billing: BillingType | null) => {
                return !!billing?.startup_program_label_previous
            },
        ],
    }),
    forms(({ values, actions }) => ({
        studentProgram: {
            defaults: {
                organization_name: values.currentOrganization?.name || '',
                organization_id: values.currentOrganizationId,
                school_name: '',
                academic_email: '',
                expected_graduation_date: undefined,
                project_description: '',
            } as StudentProgramFormValues,
            // Selector-style errors so that validation recomputes when billing
            // changes, not only when form values change
            errors: [
                (s) => [s.studentProgram, s.billing],
                (
                    {
                        organization_id,
                        school_name,
                        academic_email,
                        expected_graduation_date,
                        project_description,
                    }: StudentProgramFormValues,
                    billing: BillingType | null
                ) => {
                    if (!billing?.has_active_subscription) {
                        return {
                            _form: 'You need to upgrade to a paid plan before submitting your application',
                        }
                    }

                    return {
                        organization_id: !organization_id ? 'Please select an organization' : undefined,
                        school_name: validateSchoolName(school_name),
                        academic_email: validateAcademicEmail(academic_email),
                        expected_graduation_date: validateGraduationDate(expected_graduation_date),
                        project_description: !project_description?.trim()
                            ? 'Please tell us what you are building'
                            : undefined,
                    }
                },
            ],
            submit: async (formValues: StudentProgramFormValues) => {
                const valuesToSubmit: Record<string, any> = {
                    program: STUDENT_PROGRAM_TYPE,
                    organization_id: formValues.organization_id,
                    school_name: formValues.school_name.trim(),
                    academic_email: formValues.academic_email,
                    expected_graduation_date: dayjs.isDayjs(formValues.expected_graduation_date)
                        ? formValues.expected_graduation_date.format('YYYY-MM-DD')
                        : undefined,
                    project_description: formValues.project_description.trim(),
                }

                try {
                    await api.create('api/billing/students/apply', valuesToSubmit)
                    actions.setFormSubmitted(true)
                    // $set marks the person as a student so lifecycle flows (e.g. onboarding) can filter on it
                    posthog.capture('student program application submitted', {
                        ...valuesToSubmit,
                        $set: { student: true },
                    })
                } catch (error: any) {
                    lemonToast.error(error.detail || 'Failed to submit application')
                    throw error
                }
            },
        },
    })),
])
