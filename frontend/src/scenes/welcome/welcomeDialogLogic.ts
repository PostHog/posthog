export const welcomeDialogLogic = kea<welcomeDialogLogicType>([
    path(['scenes', 'welcome', 'welcomeDialogLogic']),

    connect(() => ({
        values: [userLogic, ['user', 'isProvisionedUser']],
    })),

    actions({
        dismissWelcome: true,
        closeDialog: (source: WelcomeCloseSource) => ({ source }),
        resetForOrgChange: true,
        trackCardClick: (card: WelcomeCardKind, targetHref: string) => ({ card, targetHref }),
        markCardInteracted: (card: WelcomeCardKind) => ({ card }),
        markShown: true,
        markOnScreen: true,
        setWelcomeDataError: (error: boolean) => ({ error }),
        // Bumped when another tab writes to localStorage (dismisses) so the current tab's
        // shouldShowDialog selector re-evaluates without needing a full page navigation.
        acknowledgeStorageChange: true,
    }),

    reducers({
        shownAt: [
            null as number | null,
            {
                markShown: () => Date.now(),
                resetForOrgChange: () => null,
            },
        ],
        // True once this tab puts the dialog on screen, which happens before the welcome data
        // arrives. `shownAt` cannot carry this, because it starts at the data, and it measures how
        // long the content stayed on screen.
        onScreen: [
            false,
            {
                markOnScreen: () => true,
                resetForOrgChange: () => false,
            },
        ],
        interactedCards: [
            {} as Record<WelcomeCardKind, boolean>,
            {
                markCardInteracted: (state, { card }) => ({ ...state, [card]: true }),
                resetForOrgChange: () => ({}) as Record<WelcomeCardKind, boolean>,
            },
        ],
        // Hide the dialog optimistically so it doesn't flash back during the loadUser refetch.
        locallyClosed: [
            false,
            {
                dismissWelcome: () => true,
                closeDialog: () => true,
                resetForOrgChange: () => false,
            },
        ],
        hasLoadedOnce: [
            false,
            {
                loadWelcomeDataSuccess: () => true,
                resetForOrgChange: () => false,
            },
        ],
        welcomeDataError: [
            false,
            {
                setWelcomeDataError: (_, { error }) => error,
                loadWelcomeData: () => false,
                resetForOrgChange: () => false,
            },
        ],
        // A monotonically-incrementing counter that shouldShowDialog depends on so cross-tab
        // localStorage changes trigger a re-computation of the selector.
        storageTick: [
            0,
            {
                acknowledgeStorageChange: (state) => state + 1,
                resetForOrgChange: () => 0,
            },
        ],
    }),

    loaders(({ actions }) => ({
        welcomeData: [
            EMPTY_PAYLOAD,
            {
                loadWelcomeData: async () => {
                    try {
                        return await api.get<WelcomePayload>('api/organizations/@current/welcome/current/')
                    } catch (error) {
                        const status =
                            typeof error === 'object' && error !== null && 'status' in error
                                ? (error as { status?: unknown }).status
                                : undefined
                        console.warn('Failed to load welcome data', error)
                        actions.setWelcomeDataError(true)
                        // Surface in PostHog so fleet-level error rate is observable; console.warn
                        // alone is invisible at scale.
                        posthog.capture('welcome_screen_load_failed', { status })
                        return EMPTY_PAYLOAD
                    }
                },
            },
        ],
    })),

    selectors({
        inviter: [(s) => [s.welcomeData], (data: WelcomePayload): WelcomeInviter | null => data.inviter],
        teamMembers: [(s) => [s.welcomeData], (data: WelcomePayload): WelcomeTeamMember[] => data.team_members],
        recentActivity: [
            (s) => [s.welcomeData],
            (data: WelcomePayload): WelcomeRecentActivity[] => data.recent_activity,
        ],
        popularDashboards: [
            (s) => [s.welcomeData],
            (data: WelcomePayload): WelcomePopularDashboard[] => data.popular_dashboards,
        ],
        productsInUse: [(s) => [s.welcomeData], (data: WelcomePayload): string[] => data.products_in_use],
        suggestedNextSteps: [
            (s) => [s.welcomeData],
            (data: WelcomePayload): WelcomeSuggestedStep[] => data.suggested_next_steps,
        ],
        organizationName: [
            (s) => [s.welcomeData, s.user],
            (data: WelcomePayload, user: null | import('../../types').UserType): string => {
                const userOrgName = user?.organization?.name
                // After an org switch the cached payload still names the previous org until the
                // refetch lands. Prefer the user's current org so the title never lags behind.
                if (userOrgName && data.organization_name && data.organization_name !== userOrgName) {
                    return userOrgName
                }
                return data.organization_name || userOrgName || ''
            },
        ],
        // Open for invitees (not the org creator) and for partner-provisioned accounts (which have no
        // inviter, so they'd otherwise never see it), when the user has neither dismissed it nor
        // already been introduced.
        // `storageTick` is in the dependency list so cross-tab localStorage changes re-run the selector.
        shouldShowDialog: [
            (s) => [s.user, s.isProvisionedUser, s.locallyClosed, s.onScreen, s.storageTick],
            (
                user: null | import('../../types').UserType,
                isProvisionedUser: boolean,
                locallyClosed: boolean,
                onScreen: boolean
            ): boolean => {
                if (!user || (user.is_organization_first_user !== false && !isProvisionedUser)) {
                    return false
                }
                const orgId = user.organization?.id
                // A dismissal is deliberate, so it closes the dialog in every tab, including one
                // that has it open.
                if (wasWelcomeDismissed(user.uuid, orgId)) {
                    return false
                }
                if (locallyClosed) {
                    return false
                }
                // This tab already put the dialog on screen. Another tab that records the
                // introduction at the same moment must not pull it back off, whether this tab is
                // still loading the content or already shows it.
                if (onScreen) {
                    return true
                }
                return !hasMarker(LOCAL_SEEN_KEY_PREFIX, user.uuid, orgId)
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        resetForOrgChange: () => {
            // The cached payload belongs to the previous org. Refetch so the members, dashboards,
            // activity, and org name all reflect the org the user just switched to. The automatic
            // refetch only fires when `shouldShowDialog` flips, which it does not when the dialog
            // was eligible in both orgs.
            actions.loadWelcomeData()
        },
        loadWelcomeDataSuccess: ({ welcomeData }) => {
            if (!values.shouldShowDialog || values.welcomeDataError) {
                return
            }
            if (!welcomeData.organization_name) {
                // Empty payload = backend error that was caught and returned EMPTY_PAYLOAD.
                return
            }
            actions.markShown()
            // After an organization switch `shouldShowDialog` stays true, so its subscription does
            // not fire and the content arrives with `onScreen` still false.
            actions.markOnScreen()
            // Record the introduction as it happens, because the user does not have to close the
            // dialog for it to count as seen.
            rememberMarker(LOCAL_SEEN_KEY_PREFIX, values.user?.uuid, values.user?.organization?.id)
            posthog.capture('welcome_screen_shown', {
                org_id: values.user?.organization?.id,
                num_team_members: welcomeData.team_members.length,
                products_in_use: welcomeData.products_in_use,
                had_recent_activity: welcomeData.recent_activity.length > 0,
                from_invite_type: welcomeData.inviter ? 'invite' : 'unknown',
            })
        },
        closeDialog: ({ source }) => {
            posthog.capture('welcome_screen_closed', {
                source,
                time_on_screen_ms: values.shownAt ? Date.now() - values.shownAt : null,
                cards_interacted_with: Object.keys(values.interactedCards).length,
            })
        },
        dismissWelcome: () => {
            const interactedCount = Object.keys(values.interactedCards).length
            const timeOnScreen = values.shownAt ? Date.now() - values.shownAt : null
            rememberMarker(LOCAL_DISMISSED_KEY_PREFIX, values.user?.uuid, values.user?.organization?.id)
            posthog.capture('welcome_screen_dismissed', {
                time_on_screen_ms: timeOnScreen,
                cards_interacted_with: interactedCount,
            })
        },
        trackCardClick: ({ card, targetHref }) => {
            actions.markCardInteracted(card)
            posthog.capture('welcome_screen_card_clicked', {
                card,
                target_href: targetHref,
            })
        },
    })),

    // Re-evaluate on user changes. Triggers the initial fetch once the user loads, and re-fetches
    // when the user switches current organization so we don't render stale data across orgs.
    subscriptions(({ actions, values }) => ({
        user: (nextUser, previousUser) => {
            const prevOrgId = previousUser?.organization?.id
            const nextOrgId = nextUser?.organization?.id
            if (prevOrgId && nextOrgId && prevOrgId !== nextOrgId) {
                actions.resetForOrgChange()
            }
        },
        shouldShowDialog: (shouldShow: boolean) => {
            if (shouldShow && !values.onScreen) {
                actions.markOnScreen()
            }
            if (shouldShow && !values.hasLoadedOnce && !values.welcomeDataLoading) {
                actions.loadWelcomeData()
            }
        },
    })),

    // Subscribe to the browser's storage event so that an introduction or a dismissal in another
    // tab propagates to this one. The event only fires in *other* tabs (not the one that performed
    // the write), so the acting tab is already in sync via its own reducers.
    events(({ actions, cache }) => ({
        afterMount: () => {
            if (typeof window === 'undefined') {
                return
            }
            const handler = (event: StorageEvent): void => {
                if (event.key && isSuppressionKey(event.key)) {
                    actions.acknowledgeStorageChange()
                }
            }
            window.addEventListener('storage', handler)
            cache.storageHandler = handler
        },
        beforeUnmount: () => {
            if (typeof window === 'undefined' || !cache.storageHandler) {
                return
            }
            window.removeEventListener('storage', cache.storageHandler)
            cache.storageHandler = undefined
        },
    })),
])
