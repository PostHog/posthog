import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import posthog from 'posthog-js'

import { inFlightRequestsLogic } from 'lib/logic/inFlightRequestsLogic'
import { ScenePage, isSameScenePage, isSameScenePath } from 'scenes/scenes'

export const SCENE_LOAD_SETTLED_EVENT = 'scene_load_settled'
export const SCENE_LOAD_ABANDONED_EVENT = 'scene_load_abandoned'
export const SETTLE_WINDOW_MS = 500

export type SceneLoadTrigger = 'page_load' | 'navigation' | 'params_change'

export interface SceneLoadCycle {
    sceneId: string
    trigger: SceneLoadTrigger
    startedAt: number
    firstRequestAt: number | null
    idleSince: number | null
    requestCount: number
    failedRequestCount: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneLoadTimingLogicValues {
    inFlightRequests: number // inFlightRequestsLogic
    currentPage: ScenePage | null
    cycle: SceneLoadCycle | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneLoadTimingLogicActions {
    requestFinished: (failed: boolean) => {
        failed: boolean
    } // inFlightRequestsLogic
    requestStarted: () => {
        startedAt: number
    } // inFlightRequestsLogic
    finishCycle: () => {
        value: true
    }
    markIdle: () => {
        at: number
    }
    sceneLoadStarted: (page: ScenePage) => {
        page: ScenePage
    }
    settle: () => {
        value: true
    }
    startCycle: (
        sceneId: string,
        trigger: SceneLoadTrigger,
        startedAt: number
    ) => {
        sceneId: string
        startedAt: number
        trigger: SceneLoadTrigger
    }
}

export type sceneLoadTimingLogicType = MakeLogicType<sceneLoadTimingLogicValues, sceneLoadTimingLogicActions>

export const sceneLoadTimingLogic = kea<sceneLoadTimingLogicType>([
    path(['scenes', 'sceneLoadTimingLogic']),
    connect(() => ({
        values: [inFlightRequestsLogic, ['inFlightRequests']],
        actions: [inFlightRequestsLogic, ['requestStarted', 'requestFinished']],
    })),
    actions({
        sceneLoadStarted: (page: ScenePage) => ({ page }),
        startCycle: (sceneId: string, trigger: SceneLoadTrigger, startedAt: number) => ({
            sceneId,
            trigger,
            startedAt,
        }),
        markIdle: () => ({ at: performance.now() }),
        settle: true,
        finishCycle: true,
    }),
    reducers({
        currentPage: [
            null as ScenePage | null,
            {
                sceneLoadStarted: (_, { page }) => page,
            },
        ],
        cycle: [
            null as SceneLoadCycle | null,
            {
                startCycle: (_, { sceneId, trigger, startedAt }) => ({
                    sceneId,
                    trigger,
                    startedAt,
                    firstRequestAt: null,
                    idleSince: null,
                    requestCount: 0,
                    failedRequestCount: 0,
                }),
                requestStarted: (cycle, { startedAt }) =>
                    cycle && {
                        ...cycle,
                        firstRequestAt: cycle.firstRequestAt ?? startedAt,
                        idleSince: null,
                        requestCount: cycle.requestCount + 1,
                    },
                requestFinished: (cycle, { failed }) =>
                    cycle && { ...cycle, failedRequestCount: cycle.failedRequestCount + (failed ? 1 : 0) },
                markIdle: (cycle, { at }) => cycle && { ...cycle, idleSince: at },
                finishCycle: () => null,
            },
        ],
    }),
    listeners(({ actions, values, cache, selectors }) => ({
        sceneLoadStarted: ({ page }, _, __, previousState) => {
            const previous = selectors.currentPage(previousState) ?? {}
            const samePath = isSameScenePath(previous, page)
            if (samePath && (values.cycle !== null || isSameScenePage(previous, page))) {
                return
            }
            actions.settle()
            const cycle = values.cycle
            if (cycle && cycle.requestCount > 0) {
                posthog.capture(SCENE_LOAD_ABANDONED_EVENT, {
                    scene: cycle.sceneId,
                    trigger: cycle.trigger,
                    duration_ms: Math.round(performance.now() - cycle.startedAt),
                    request_count: cycle.requestCount,
                    failed_request_count: cycle.failedRequestCount,
                    requests_in_flight: values.inFlightRequests,
                })
            }
            actions.finishCycle()
            if (!previous.sceneId) {
                actions.startCycle(page.sceneId, 'page_load', 0)
            } else {
                actions.startCycle(page.sceneId, samePath ? 'params_change' : 'navigation', performance.now())
            }
        },
        requestStarted: () => {
            cache.disposables.dispose('settle')
        },
        requestFinished: () => {
            if (values.cycle && values.inFlightRequests === 0) {
                actions.markIdle()
            }
        },
        markIdle: () => {
            cache.disposables.add(() => {
                const timer = window.setTimeout(actions.settle, SETTLE_WINDOW_MS)
                return () => window.clearTimeout(timer)
            }, 'settle')
        },
        settle: () => {
            const cycle = values.cycle
            if (!cycle || cycle.idleSince === null) {
                return
            }
            if (cycle.requestCount > 0) {
                posthog.capture(SCENE_LOAD_SETTLED_EVENT, {
                    scene: cycle.sceneId,
                    trigger: cycle.trigger,
                    duration_ms: Math.round(cycle.idleSince - cycle.startedAt),
                    time_to_first_request_ms: Math.round((cycle.firstRequestAt ?? cycle.idleSince) - cycle.startedAt),
                    request_count: cycle.requestCount,
                    failed_request_count: cycle.failedRequestCount,
                })
            }
            actions.finishCycle()
        },
        finishCycle: () => {
            cache.disposables.dispose('settle')
        },
    })),
])
