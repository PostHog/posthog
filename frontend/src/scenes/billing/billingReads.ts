/**
 * The billing reads the usage and spend pages make, from the organization billing API. The pages never name a route.
 *
 * Each method maps the API's answer into the shape the pages consume.
 */
export interface BillingReads {
    usageSeries(params: BillingUsageTimeseriesRetrieveParams): Promise<BillingUsageResponse>
    spendSeries(params: BillingSpendTimeseriesRetrieveParams): Promise<BillingSpendResponse>
    usageExportUrl(params: BillingUsageExportDownloadParams): string
    spendExportUrl(params: BillingSpendExportDownloadParams): string
    /** The ids of the projects that reported usage, live and deleted. */
    reportedProjectIds(): Promise<number[]>
}

// The API describes a series with every field optional, and the charts draw only complete ones.
// The pages' breakdown enums hold the same strings as the generated one.
function chartSeries<Response extends BillingUsageResponse | BillingSpendResponse>(
    points: BillingTimeSeriesPointApi[]
): Response['results'] {
    return points.map((point) => ({
        id: point.id ?? 0,
        label: point.label ?? '',
        data: point.data ?? [],
        dates: point.dates ?? [],
        breakdown_type: point.breakdown_type ?? null,
        breakdown_value: (point.breakdown_value as string | string[] | null | undefined) ?? null,
    })) as Response['results']
}

export function organizationBillingReads(organizationId: string): BillingReads {
    return {
        usageSeries: async (params) => {
            const { count, next, previous, results } = await billingUsageTimeseriesRetrieve(organizationId, params)
            return { count, next, previous, results: chartSeries<BillingUsageResponse>(results) }
        },
        spendSeries: async (params) => {
            const {
                count,
                next,
                previous,
                results,
                pricing_reset_dates = [],
            } = await billingSpendTimeseriesRetrieve(organizationId, params)
            return {
                count,
                next,
                previous,
                results: chartSeries<BillingSpendResponse>(results),
                pricing_reset_dates,
            }
        },
        usageExportUrl: (params) => getBillingUsageExportDownloadUrl(organizationId, params),
        spendExportUrl: (params) => getBillingSpendExportDownloadUrl(organizationId, params),
        reportedProjectIds: async () => (await billingProjectList(organizationId)).results.map((project) => project.id),
    }
}

