import { MakeLogicType, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import { billingAiCreditsRetrieve, billingAiCreditsTopUpCreate } from 'products/billing/frontend/generated/api'
import type {
    AICreditTopUpApi,
    AICreditTopUpResponseApi,
    AICreditTopUpRejectionEnumApi,
    AICreditsResponseApi,
} from 'products/billing/frontend/generated/api.schemas'

// Billing waits for tax before it charges the card, so a top-up can take several minutes to land.
export const AI_CREDITS_POLL_INTERVAL_MS = 5000

const REJECTION_MESSAGES: Record<AICreditTopUpRejectionEnumApi, string> = {
    not_available: "AI credits aren't available for your organization.",
    top_up_in_flight: 'A purchase is already processing. Try again once it finishes.',
    no_payment_method: 'Add a payment card in your billing details, then try again.',
    customer_balance_not_zero:
        "Your account has a balance on it, so we can't charge your card for AI credits. Contact support to buy them.",
}

export const isTopUpInFlight = (topUp: AICreditTopUpApi): boolean =>
    topUp.status === 'awaiting_tax' || topUp.status === 'paid'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiCreditsLogicValues {
    aiCredits: AICreditsResponseApi | null
    aiCreditsLoading: boolean
    inFlightTopUp: AICreditTopUpApi | null
    pendingTopUpAmount: number | null
    topUpProcessing: boolean
    topUpResponse: AICreditTopUpResponseApi | null
    topUpResponseLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiCreditsLogicActions {
    loadAiCredits: () => any
    loadAiCreditsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAiCreditsSuccess: (
        aiCredits: AICreditsResponseApi | null,
        payload?: any
    ) => {
        aiCredits: AICreditsResponseApi | null
        payload?: any
    }
    topUp: (amountUsd: number) => number
    topUpFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    topUpSuccess: (
        topUpResponse: AICreditTopUpResponseApi,
        payload?: number
    ) => {
        topUpResponse: AICreditTopUpResponseApi
        payload?: number
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface aiCreditsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        inFlightTopUp: (aiCredits: AICreditsResponseApi | null) => AICreditTopUpApi | null
        topUpProcessing: (
            inFlightTopUp: AICreditTopUpApi | null,
            topUpResponse: AICreditTopUpResponseApi | null,
            aiCredits: AICreditsResponseApi | null
        ) => boolean
    }
}

export type aiCreditsLogicType = MakeLogicType<
    aiCreditsLogicValues,
    aiCreditsLogicActions,
    Record<string, any>,
    aiCreditsLogicMeta
>

export const aiCreditsLogic = kea<aiCreditsLogicType>([
    path(['scenes', 'billing', 'aiCreditsLogic']),
    loaders(({ values }) => ({
        aiCredits: [
            null as AICreditsResponseApi | null,
            {
                loadAiCredits: async () => {
                    try {
                        return await billingAiCreditsRetrieve()
                    } catch {
                        // The section is optional, so a failed read keeps the last answer instead of toasting on every poll.
                        return values.aiCredits
                    }
                },
            },
        ],
        topUpResponse: [
            null as AICreditTopUpResponseApi | null,
            {
                topUp: async (amountUsd: number) => await billingAiCreditsTopUpCreate({ amount_usd: amountUsd }),
            },
        ],
    })),
    reducers({
        pendingTopUpAmount: [
            null as number | null,
            {
                topUp: (_, amountUsd) => amountUsd,
                topUpSuccess: () => null,
                topUpFailure: () => null,
            },
        ],
    }),
    selectors({
        inFlightTopUp: [
            (s) => [s.aiCredits],
            (aiCredits: AICreditsResponseApi | null): AICreditTopUpApi | null =>
                aiCredits?.top_ups?.find(isTopUpInFlight) ?? null,
        ],
        topUpProcessing: [
            (s) => [s.inFlightTopUp, s.topUpResponse, s.aiCredits],
            (
                inFlightTopUp: AICreditTopUpApi | null,
                topUpResponse: AICreditTopUpResponseApi | null,
                aiCredits: AICreditsResponseApi | null
            ): boolean => {
                // An accepted purchase counts until a read lists it, in case the read after the purchase failed.
                const acceptedId = topUpResponse?.status === 'rejected' ? undefined : topUpResponse?.id
                const unlisted =
                    acceptedId !== undefined && !aiCredits?.top_ups?.some((topUp) => topUp.id === acceptedId)
                return !!inFlightTopUp || unlisted
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        topUpSuccess: ({ topUpResponse }) => {
            if (topUpResponse?.status === 'rejected') {
                lemonToast.error(
                    topUpResponse.reason
                        ? REJECTION_MESSAGES[topUpResponse.reason]
                        : "We couldn't start the purchase. Try again."
                )
            }
            actions.loadAiCredits()
        },
        topUpFailure: () => {
            // The purchase may have started before the request failed, so show what billing holds.
            actions.loadAiCredits()
        },
        loadAiCreditsSuccess: () => {
            if (values.topUpProcessing) {
                cache.disposables.add(() => {
                    const timeout = window.setTimeout(() => actions.loadAiCredits(), AI_CREDITS_POLL_INTERVAL_MS)
                    return () => clearTimeout(timeout)
                }, 'aiCreditsPoll')
            } else {
                cache.disposables.dispose('aiCreditsPoll')
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadAiCredits()
    }),
])
