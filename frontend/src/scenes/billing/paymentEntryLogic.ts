const PAYMENT_ORGANIZATION_ERROR = 'This payment link is missing its organization. Return to billing and start again.'

export const paymentEntryLogic = kea<paymentEntryLogicType>([
    path(['scenes', 'billing', 'PaymentEntryLogic']),
    actions({
        setClientSecret: (clientSecret: string | null) => ({ clientSecret }),
        setLoading: (loading: boolean) => ({ loading }),
        setStripeError: (error: string | null) => ({ error }),
        setApiError: (error: string | null) => ({ error }),
        clearErrors: true,
        beginPaymentFlow: (organizationId: string, redirectPath: string | null = null) => ({
            organizationId,
            redirectPath,
            organizationName:
                organizationLogic.values.currentOrganization?.id === organizationId
                    ? organizationLogic.values.currentOrganization.name
                    : null,
        }),
        refreshPaymentOrganization: (organizationId: string) => ({ organizationId }),
        completePaymentFlow: (
            organizationId: string,
            successParam: 'success' | 'upgraded',
            redirectPath: string | null
        ) => ({ organizationId, successParam, redirectPath }),
        setCompletedPaymentOrganization: (organization: { id: string; name: string }) => ({ organization }),
        viewCompletedPaymentOrganization: true,
        initiateAuthorization: true,
        pollAuthorizationStatus: (paymentIntentId?: string) => ({ paymentIntentId }),
        setAuthorizationStatus: (status: string | null) => ({ status }),
        startPaymentEntryFlow: (product?: BillingProductV2Type | null, redirectPath?: string | null) => ({
            product,
            redirectPath,
        }),
        showPaymentEntryModal: true,
        hidePaymentEntryModal: true,
        setRedirectPath: (redirectPath: string | null) => ({ redirectPath }),
    }),
    reducers({
        paymentOrganizationId: [null as string | null, { beginPaymentFlow: (_, { organizationId }) => organizationId }],
        paymentOrganizationName: [
            null as string | null,
            { beginPaymentFlow: (_, { organizationName }) => organizationName },
        ],
        completedPaymentOrganization: [
            null as { id: string; name: string } | null,
            {
                setCompletedPaymentOrganization: (_, { organization }) => organization,
                beginPaymentFlow: () => null,
                hidePaymentEntryModal: () => null,
            },
        ],
        paymentFlowId: [0, { beginPaymentFlow: (id) => id + 1, hidePaymentEntryModal: (id) => id + 1 }],
        clientSecret: [
            null as string | null,
            {
                setClientSecret: (_, { clientSecret }) => clientSecret,
                beginPaymentFlow: () => null,
                hidePaymentEntryModal: () => null,
            },
        ],
        isLoading: [
            false,
            {
                setLoading: (_, { loading }) => loading,
                beginPaymentFlow: () => false,
                hidePaymentEntryModal: () => false,
            },
        ],
        stripeError: [
            null as string | null,
            { setStripeError: (_, { error }) => error, clearErrors: () => null, beginPaymentFlow: () => null },
        ],
        apiError: [
            null as string | null,
            { setApiError: (_, { error }) => error, clearErrors: () => null, beginPaymentFlow: () => null },
        ],
        authorizationStatus: [
            null as string | null,
            { setAuthorizationStatus: (_, { status }) => status, beginPaymentFlow: () => null },
        ],
        paymentEntryModalOpen: [false, { showPaymentEntryModal: () => true, hidePaymentEntryModal: () => false }],
        redirectPath: [
            null as string | null,
            {
                setRedirectPath: (_, { redirectPath }) => redirectPath,
                beginPaymentFlow: (_, { redirectPath }) => redirectPath,
            },
        ],
    }),
    selectors({
        stripeReturnUrl: [
            (s) => [s.paymentOrganizationId, s.redirectPath],
            (organizationId: string | null, redirectPath: string | null): string | null => {
                if (!organizationId) {
                    return null
                }
                const url = new URL(urls.billingAuthorizationStatus(), window.location.origin)
                url.searchParams.set('organization_id', organizationId)
                if (redirectPath) {
                    url.searchParams.set('postRedirectPath', redirectPath)
                }
                return url.toString()
            },
        ],
    }),
    listeners(({ actions, asyncActions, values, cache }) => ({
        beginPaymentFlow: () => {
            cache.disposables.dispose('authorizationPoll')
        },
        refreshPaymentOrganization: async ({ organizationId }) => {
            const flowId = values.paymentFlowId
            if (organizationLogic.values.currentOrganization?.id !== organizationId) {
                return
            }
            await billingLogic.asyncActions.loadBilling(organizationId)
            if (cache.disposables.isDisposed || values.paymentFlowId !== flowId) {
                return
            }
            try {
                // Generated organization teams/features are readonly generic arrays. The existing
                // state uses OrganizationType for this same wire payload and its entitlement fields.
                const organization = (await retrieveOrganization(organizationId)) as unknown as OrganizationType
                if (
                    cache.disposables.isDisposed ||
                    values.paymentFlowId !== flowId ||
                    organizationLogic.values.currentOrganization?.id !== organizationId
                ) {
                    return
                }
                const user = userLogic.values.user
                if (organization.id !== organizationId || user?.organization?.id !== organizationId) {
                    return
                }
                organizationLogic.actions.loadCurrentOrganizationSuccess(organization)
                userLogic.actions.loadUserSuccess({ ...user, organization })
            } catch {
                // Keep the selected organization if its entitlement refresh fails.
            }
        },
        completePaymentFlow: async ({ organizationId, successParam, redirectPath }) => {
            const flowId = values.paymentFlowId
            const active = (): boolean => !cache.disposables.isDisposed && flowId === values.paymentFlowId
            try {
                await asyncActions.refreshPaymentOrganization(organizationId)
            } catch {
                // Payment is confirmed even if its billing or entitlement refresh fails.
            }
            if (!active()) {
                return
            }
            if (organizationLogic.values.currentOrganization?.id !== organizationId) {
                const name = values.paymentOrganizationName || 'the original organization'
                actions.setCompletedPaymentOrganization({ id: organizationId, name })
                actions.setLoading(false)
                actions.setClientSecret(null)
                actions.setRedirectPath(null)
                actions.clearErrors()
                if (router.values.location.pathname !== urls.billingAuthorizationStatus()) {
                    actions.showPaymentEntryModal()
                }
                if (!values.paymentOrganizationName) {
                    try {
                        const organization = await retrieveOrganization(organizationId)
                        if (
                            active() &&
                            values.completedPaymentOrganization?.id === organizationId &&
                            organization.id === organizationId &&
                            organization.name
                        ) {
                            actions.setCompletedPaymentOrganization({ id: organizationId, name: organization.name })
                        }
                    } catch {
                        // Keep the truthful fallback rather than reporting a confirmed payment as failed.
                    }
                }
                return
            }
            const destination =
                redirectPath ||
                (router.values.location.pathname === urls.billingAuthorizationStatus()
                    ? urls.organizationBilling()
                    : router.values.location.pathname)
            const url = new URL(destination, window.location.origin)
            router.actions.push(url.pathname, {
                ...Object.fromEntries(url.searchParams.entries()),
                [successParam]: successParam === 'upgraded' ? 'true' : true,
            })
            actions.hidePaymentEntryModal()
        },
        viewCompletedPaymentOrganization: () => {
            const organization = values.completedPaymentOrganization
            if (organization) {
                userLogic.actions.updateCurrentOrganization(organization.id, urls.organizationBilling())
            }
        },
        startPaymentEntryFlow: async ({ product, redirectPath }) => {
            const { billing, billingManagedByPartnerNotice } = billingLogic.values
            if (billingManagedByPartnerNotice) {
                lemonToast.info(billingManagedByPartnerNotice)
                return
            }
            const organizationId = organizationLogic.values.currentOrganization?.id
            if (!organizationId) {
                lemonToast.error('Reload the page before updating payment details.')
                return
            }
            actions.beginPaymentFlow(organizationId, redirectPath || null)
            const flowId = values.paymentFlowId
            if (billing?.customer_id) {
                actions.setLoading(true)
                if (product) {
                    billingProductLogic({ product }).actions.setBillingProductLoading(product.type)
                }
                try {
                    const response = await billingActivateCreate({
                        organization_id: organizationId,
                        products: 'all_products:',
                        ...(product?.type ? { intent_product: product.type } : {}),
                    })
                    if (cache.disposables.isDisposed || flowId !== values.paymentFlowId) {
                        return
                    }
                    if (response.success) {
                        await asyncActions.completePaymentFlow(organizationId, 'upgraded', redirectPath || null)
                    } else if (response.must_setup_payment) {
                        actions.showPaymentEntryModal()
                    } else {
                        lemonToast.error(response.error || 'Failed to activate subscription')
                    }
                } catch (error) {
                    if (cache.disposables.isDisposed || flowId !== values.paymentFlowId) {
                        return
                    }
                    posthog.captureException(
                        new Error('payment entry api error - activate subscription error', { cause: error })
                    )
                    lemonToast.error('Failed to activate subscription. Please try again.')
                } finally {
                    if (!cache.disposables.isDisposed && flowId === values.paymentFlowId) {
                        actions.setLoading(false)
                    }
                    if (product) {
                        billingProductLogic({ product }).actions.setBillingProductLoading(null)
                    }
                }
                return
            }
            actions.showPaymentEntryModal()
        },
        initiateAuthorization: async () => {
            if (values.completedPaymentOrganization) {
                return
            }
            const organizationId = values.paymentOrganizationId
            const flowId = values.paymentFlowId
            if (!organizationId) {
                actions.setApiError(PAYMENT_ORGANIZATION_ERROR)
                return
            }
            actions.setClientSecret(null)
            actions.setLoading(true)
            actions.clearErrors()
            try {
                const response = await billingActivateAuthorizeCreate({ organization_id: organizationId })
                if (cache.disposables.isDisposed || flowId !== values.paymentFlowId) {
                    return
                }
                actions.setClientSecret(response.clientSecret || null)
            } catch (error) {
                if (cache.disposables.isDisposed || flowId !== values.paymentFlowId) {
                    return
                }
                posthog.captureException(
                    new Error('payment entry api error - initiate authorization error', { cause: error })
                )
                actions.setApiError('Failed to initialize payment')
            } finally {
                if (!cache.disposables.isDisposed && flowId === values.paymentFlowId) {
                    actions.setLoading(false)
                }
            }
        },
        pollAuthorizationStatus: async ({ paymentIntentId }) => {
            const organizationId = values.paymentOrganizationId
            const flowId = values.paymentFlowId
            const redirectPath = values.redirectPath
            const intentId = paymentIntentId || new URLSearchParams(window.location.search).get('payment_intent')
            if (!organizationId) {
                actions.setApiError(PAYMENT_ORGANIZATION_ERROR)
                return
            }
            cache.disposables.dispose('authorizationPoll')
            actions.setLoading(true)
            let attempts = 0
            const active = (): boolean => !cache.disposables.isDisposed && flowId === values.paymentFlowId
            const poll = async (): Promise<void> => {
                if (!active()) {
                    return
                }
                let terminal = true
                try {
                    const response = await billingActivateAuthorizeStatusCreate({
                        organization_id: organizationId,
                        payment_intent_id: intentId,
                    })
                    if (!active()) {
                        return
                    }
                    const status = response.status || (response.success ? 'success' : 'failed')
                    actions.setAuthorizationStatus(status)
                    if (status === 'success') {
                        await asyncActions.completePaymentFlow(organizationId, 'success', redirectPath)
                    } else if (status === 'failed') {
                        actions.setApiError(response.error || 'Payment failed. Please try again.')
                    } else if (++attempts < 30) {
                        terminal = false
                        cache.disposables.add(() => {
                            const timer = setTimeout(() => void poll(), 2000)
                            return () => clearTimeout(timer)
                        }, 'authorizationPoll')
                    } else {
                        actions.setApiError('Payment status check timed out')
                    }
                } catch (error) {
                    if (!active()) {
                        return
                    }
                    actions.setApiError('Failed to complete. Please refresh the page and try again.')
                    posthog.captureException(new Error('payment entry api error', { cause: error }))
                } finally {
                    if (terminal && active()) {
                        actions.setLoading(false)
                        actions.setClientSecret(null)
                        actions.setRedirectPath(null)
                    }
                }
            }
            await poll()
        },
        hidePaymentEntryModal: () => {
            cache.disposables.dispose('authorizationPoll')
            actions.clearErrors()
        },
    })),
    afterMount(({ actions }) => {
        const params = new URLSearchParams(window.location.search)
        const organizationId = params.get('organization_id')
        if (organizationId && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(organizationId)) {
            actions.beginPaymentFlow(organizationId, params.get('postRedirectPath'))
        }
    }),
])
