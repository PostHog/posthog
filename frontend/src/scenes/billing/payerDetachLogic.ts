import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { lemonToast } from '@posthog/lemon-ui'

import { ApiError } from 'lib/api-error'
import { OrganizationMembershipLevel } from 'lib/constants'
import { organizationLogic } from 'scenes/organizationLogic'

import { billingPayerDetachCreate } from 'products/billing/frontend/generated/api'

import type { OrganizationType } from '../../types'
import { billingLogic } from './billingLogic'

const PAYER_DETACH_UNCONFIRMED_MESSAGE =
    "We couldn't confirm the change with billing. Try again; it's safe to repeat. If it keeps happening, contact support."

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface payerDetachLogicValues {
    billingPartnerName: string | null // billingLogic
    isBillingManagedByPartner: boolean // billingLogic
    currentOrganization: OrganizationType | null // organizationLogic
    canDetachFromPayer: boolean
    detachedOrganizationId: string | null
    isDetachingFromPayer: boolean
    isPayerDetachModalOpen: boolean
    payerDetachError: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface payerDetachLogicActions {
    loadBilling: () => any // billingLogic
    closePayerDetachModal: () => {
        value: true
    }
    detachFromPayer: () => {
        value: true
    }
    detachFromPayerFailure: (error: string) => {
        error: string
    }
    detachFromPayerSuccess: (organizationId: string) => {
        organizationId: string
    }
    openPayerDetachModal: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface payerDetachLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        canDetachFromPayer: (
            isBillingManagedByPartner: boolean,
            currentOrganization: OrganizationType | null,
            detachedOrganizationId: string | null
        ) => boolean
    }
}

export type payerDetachLogicType = MakeLogicType<
    payerDetachLogicValues,
    payerDetachLogicActions,
    Record<string, any>,
    payerDetachLogicMeta
>

export const payerDetachLogic = kea<payerDetachLogicType>([
    path(['scenes', 'billing', 'payerDetachLogic']),
    connect(() => ({
        values: [
            billingLogic,
            ['billingPartnerName', 'isBillingManagedByPartner'],
            organizationLogic,
            ['currentOrganization'],
        ],
        actions: [billingLogic, ['loadBilling']],
    })),
    actions({
        openPayerDetachModal: true,
        closePayerDetachModal: true,
        detachFromPayer: true,
        detachFromPayerSuccess: (organizationId: string) => ({ organizationId }),
        detachFromPayerFailure: (error: string) => ({ error }),
    }),
    reducers({
        detachedOrganizationId: [
            null as string | null,
            {
                detachFromPayerSuccess: (_, { organizationId }) => organizationId,
            },
        ],
        isPayerDetachModalOpen: [
            false,
            {
                openPayerDetachModal: () => true,
                closePayerDetachModal: () => false,
                detachFromPayerSuccess: () => false,
            },
        ],
        isDetachingFromPayer: [
            false,
            {
                detachFromPayer: () => true,
                detachFromPayerSuccess: () => false,
                detachFromPayerFailure: () => false,
            },
        ],
        payerDetachError: [
            null as string | null,
            {
                openPayerDetachModal: () => null,
                detachFromPayer: () => null,
                detachFromPayerFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        canDetachFromPayer: [
            (s) => [s.isBillingManagedByPartner, s.currentOrganization, s.detachedOrganizationId],
            (
                isBillingManagedByPartner: boolean,
                currentOrganization: OrganizationType | null,
                detachedOrganizationId: string | null
            ): boolean =>
                isBillingManagedByPartner &&
                currentOrganization?.id !== detachedOrganizationId &&
                (currentOrganization?.membership_level ?? 0) >= OrganizationMembershipLevel.Owner,
        ],
    }),
    listeners(({ actions, values }) => ({
        detachFromPayer: async () => {
            const organizationId = values.currentOrganization?.id
            if (!organizationId) {
                actions.detachFromPayerFailure('Reload the page, then try again.')
                return
            }
            try {
                await billingPayerDetachCreate({ organization_id: organizationId })
            } catch (error) {
                actions.detachFromPayerFailure(
                    (error instanceof ApiError && error.detail) || PAYER_DETACH_UNCONFIRMED_MESSAGE
                )
                return
            }
            actions.detachFromPayerSuccess(organizationId)
        },
        detachFromPayerSuccess: () => {
            lemonToast.success('You now pay for this organization yourself.')
            actions.loadBilling()
        },
    })),
])
