import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router, urlToAction } from 'kea-router'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import type { FeatureFlagsSet } from '../../lib/logic/featureFlagLogic'
import { VIEW_FEED_PAGE_SIZE, ViewFeed, ViewFeedQuery, ViewSourceState } from './viewFeed'
import { selectViewFeed, viewFeedLogic } from './viewFeedLogic'
import { ViewTypeFilter } from './viewsUtils'

export const VIEWS_PREFETCH_COUNT = VIEW_FEED_PAGE_SIZE

