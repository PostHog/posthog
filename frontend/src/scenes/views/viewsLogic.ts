import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import { router, urlToAction } from 'kea-router'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { removeProjectIdIfPresent } from 'lib/utils/kea-router'
import { teamLogic } from 'scenes/teamLogic'
import { urls } from 'scenes/urls'

import { ViewItemsPage, fetchViewItems } from './fetchViewItems'
import { ViewItem, ViewTypeFilter, filterViews } from './viewsUtils'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface viewsLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentTeamId: number | null // teamLogic
    loadFailed: boolean
    search: string
    typeFilter: ViewTypeFilter
    views: ViewItemsPage | null
    viewsLoading: boolean
    visibleViews: ViewItem[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface viewsLogicActions {
    loadViews: (_: void) => void
    loadViewsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadViewsSuccess: (
        views: ViewItemsPage | null,
        payload?: void
    ) => {
        views: ViewItemsPage | null
        payload?: void
    }
    receiveViews: (page: ViewItemsPage) => {
        page: ViewItemsPage
    }
    setSearch: (search: string) => {
        search: string
    }
    setTypeFilter: (typeFilter: ViewTypeFilter) => {
        typeFilter: ViewTypeFilter
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface viewsLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        visibleViews: (views: ViewItemsPage | null, typeFilter: ViewTypeFilter) => ViewItem[]
    }
}

export type viewsLogicType = MakeLogicType<viewsLogicValues, viewsLogicActions, Record<string, any>, viewsLogicMeta>

export const viewsLogic = kea<viewsLogicType>([
    path(['scenes', 'views', 'viewsLogic']),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags'], teamLogic, ['currentTeamId']] })),
    actions({
        receiveViews: (page: ViewItemsPage) => ({ page }),
        setSearch: (search: string) => ({ search }),
        setTypeFilter: (typeFilter: ViewTypeFilter) => ({ typeFilter }),
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        typeFilter: ['all' as ViewTypeFilter, { setTypeFilter: (_, { typeFilter }) => typeFilter }],
    }),
    loaders(({ values, actions }) => ({
        views: [
            null as ViewItemsPage | null,
            {
                loadViews: async (_: void, breakpoint) => {
                    await breakpoint(250)
                    if (!values.currentTeamId) {
                        return values.views
                    }
                    const teamId = values.currentTeamId
                    const search = values.search
                    const page = await fetchViewItems(String(teamId), search, (page) => {
                        breakpoint()
                        if (values.currentTeamId === teamId && values.search === search) {
                            actions.receiveViews(page)
                        }
                    })
                    breakpoint()
                    return values.currentTeamId === teamId && values.search === search ? page : values.views
                },
            },
        ],
    })),
    reducers({
        views: {
            receiveViews: (_, { page }) => page,
        },
        loadFailed: [false, { loadViews: () => false, loadViewsFailure: () => true }],
    }),
    selectors({
        visibleViews: [
            (s) => [s.views, s.typeFilter],
            (views: ViewItemsPage | null, typeFilter: ViewTypeFilter): ViewItem[] =>
                filterViews(views?.items ?? [], typeFilter),
        ],
    }),
    listeners(({ actions, values }) => ({
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
            // Flags can arrive after urlToAction ran, so a visit that skipped the load must load now.
            if (
                values.featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV] &&
                !values.views &&
                !values.viewsLoading &&
                removeProjectIdIfPresent(router.values.location.pathname) === urls.views()
            ) {
                actions.loadViews()
            }
        },
        setSearch: () => actions.loadViews(),
        setTypeFilter: ({ typeFilter }) => {
            // pinned: analytics event name and property. Renaming them breaks dashboards.
            posthog.capture('views list filtered', { type: typeFilter })
        },
    })),
    urlToAction(({ actions, values }) => ({
        [urls.views()]: () => {
            // The Views scene renders nothing without the flag, so it must not load anything either.
            if (values.featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV]) {
                actions.loadViews()
            }
        },
    })),
])
