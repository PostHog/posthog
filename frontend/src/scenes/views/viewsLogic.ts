export type viewsLogicType = MakeLogicType<viewsLogicValues, viewsLogicActions, Record<string, any>, viewsLogicMeta>

export const viewsLogic = kea<viewsLogicType>([
    path(['scenes', 'views', 'viewsLogic']),
    connect(() => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            teamLogic,
            ['currentTeamId'],
            viewFeedLogic,
            ['sources', 'spaceNames'],
        ],
        actions: [viewFeedLogic, ['ensureFeed', 'refreshFeed', 'sourceRefreshed']],
    })),
    actions({
        setSearch: (search: string) => ({ search }),
        setFeedSearch: (search: string) => ({ search }),
        setTypeFilter: (typeFilter: ViewTypeFilter) => ({ typeFilter }),
        setShownQuery: (query: ViewFeedQuery) => ({ query }),
        loadViews: true,
        loadMoreViews: true,
    }),
    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        feedSearch: ['', { setFeedSearch: (_, { search }) => search }],
        typeFilter: ['all' as ViewTypeFilter, { setTypeFilter: (_, { typeFilter }) => typeFilter }],
        shownQuery: [null as ViewFeedQuery | null, { setShownQuery: (_, { query }) => query }],
    }),
    selectors({
        feedQuery: [
            (s) => [s.typeFilter, s.feedSearch],
            (typeFilter: ViewTypeFilter, feedSearch: string): ViewFeedQuery => ({
                type: typeFilter,
                search: feedSearch.trim(),
            }),
        ],
        currentFeed: [
            (s) => [s.sources, s.spaceNames, s.currentTeamId, s.feedQuery],
            (
                sources: Record<string, ViewSourceState>,
                spaceNames: Record<string, string>,
                currentTeamId: number | null,
                feedQuery: ViewFeedQuery
            ): ViewFeed => selectViewFeed(sources, spaceNames, currentTeamId, feedQuery),
        ],
        feed: [
            (s) => [s.currentFeed, s.sources, s.spaceNames, s.currentTeamId, s.shownQuery],
            (
                currentFeed: ViewFeed,
                sources: Record<string, ViewSourceState>,
                spaceNames: Record<string, string>,
                currentTeamId: number | null,
                shownQuery: ViewFeedQuery | null
            ): ViewFeed => {
                if (currentFeed.initialized || !shownQuery) {
                    return currentFeed
                }
                const shownFeed = selectViewFeed(sources, spaceNames, currentTeamId, shownQuery)
                return shownFeed.initialized ? { ...shownFeed, loading: true, hasMore: false } : currentFeed
            },
        ],
        feedStale: [
            (s) => [s.currentFeed, s.feed],
            (currentFeed: ViewFeed, feed: ViewFeed): boolean => !currentFeed.initialized && feed.initialized,
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const syncShownQuery = (): void => {
            if (values.currentFeed.initialized) {
                if (values.shownQuery !== values.feedQuery) {
                    actions.setShownQuery(values.feedQuery)
                }
                if (cache.visitStartedAt !== undefined) {
                    posthog.capture('views list loaded', {
                        duration_ms: Math.round(performance.now() - cache.visitStartedAt),
                        cached: cache.visitCached,
                        view_count: values.currentFeed.items.length,
                        has_more: values.currentFeed.hasMore,
                    })
                    cache.visitStartedAt = undefined
                }
            }
        }
        return {
            [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
                // Flags can arrive after urlToAction ran, so a visit that skipped the load must load now.
                if (
                    values.featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV] &&
                    cache.visitStartedAt === undefined &&
                    !values.currentFeed.initialized &&
                    !values.currentFeed.loading &&
                    removeProjectIdIfPresent(router.values.location.pathname) === urls.views()
                ) {
                    actions.loadViews()
                }
            },
            loadViews: () => {
                cache.visitStartedAt = performance.now()
                cache.visitCached = values.currentFeed.initialized
                actions.refreshFeed(values.feedQuery)
                syncShownQuery()
            },
            loadMoreViews: () => {
                actions.ensureFeed(values.feedQuery, values.feed.items.length + VIEWS_PREFETCH_COUNT)
            },
            setSearch: async ({ search }, breakpoint) => {
                if (search.trim() !== values.feedSearch.trim()) {
                    await breakpoint(search.trim() ? 200 : 0)
                }
                actions.setFeedSearch(search)
            },
            setFeedSearch: () => {
                actions.ensureFeed(values.feedQuery, VIEWS_PREFETCH_COUNT)
                syncShownQuery()
            },
            setTypeFilter: ({ typeFilter }) => {
                // pinned: analytics event name and property. Renaming them breaks dashboards.
                posthog.capture('views list filtered', { type: typeFilter })
                actions.ensureFeed(values.feedQuery, VIEWS_PREFETCH_COUNT)
                syncShownQuery()
            },
            sourceRefreshed: () => syncShownQuery(),
        }
    }),
    urlToAction(({ actions, values }) => ({
        [urls.views()]: () => {
            // The Views scene renders nothing without the flag, so it must not load anything either.
            if (values.featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV]) {
                actions.loadViews()
            }
        },
    })),
])
