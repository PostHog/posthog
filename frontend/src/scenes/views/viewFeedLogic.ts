import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { spaceLabel } from '~/layout/today/todaySpacesLogic'

import { taskChannelsList } from 'products/tasks/frontend/generated/api'
import type { ChannelDTOApi } from 'products/tasks/frontend/generated/api.schemas'

import {
    ViewFeed,
    ViewFeedQuery,
    ViewSourcePage,
    ViewSourceState,
    fetchViewSourcePage,
    mergeViewSources,
    viewFeedFromSources,
    viewFeedTypes,
    viewSourceKey,
} from './viewFeed'
import { ViewType } from './viewsUtils'

const MAX_SEARCH_SOURCES = 30

interface ViewFeedSnapshot {
    sources: Record<string, ViewSourceState>
    spaceNames: Record<string, string>
}

let snapshot: ViewFeedSnapshot | null = null

export function resetViewFeedSnapshot(): void {
    snapshot = null
}

function settledSources(sources: Record<string, ViewSourceState>): Record<string, ViewSourceState> {
    return Object.fromEntries(
        Object.entries(sources)
            .filter(([, source]) => source.initialized)
            .map(([key, source]) => [key, { ...source, refreshing: false, loading: false }])
    )
}

function withoutOldSearches(sources: Record<string, ViewSourceState>): Record<string, ViewSourceState> {
    const searchKeys = Object.keys(sources).filter((key) => sources[key].search)
    const dropped = new Set(searchKeys.slice(0, Math.max(0, searchKeys.length - MAX_SEARCH_SOURCES)))
    return dropped.size ? Object.fromEntries(Object.entries(sources).filter(([key]) => !dropped.has(key))) : sources
}

export function selectViewFeed(
    sources: Record<string, ViewSourceState>,
    spaceNames: Record<string, string>,
    projectId: number | null,
    query: ViewFeedQuery
): ViewFeed {
    return viewFeedFromSources(
        viewFeedTypes(query).map((type) =>
            projectId ? sources[viewSourceKey(String(projectId), query.search, type)] : undefined
        ),
        spaceNames
    )
}

