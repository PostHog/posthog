const teamId = window.POSTHOG_APP_CONTEXT?.current_team?.id
// Distinct prefix from webAnalyticsFilterLogic so bot-tab filters don't collide with the regular tab.
const persistConfig = { persist: true, prefix: `${teamId}__bot_` }

// The window pathname carries the /project/:id prefix and may keep a trailing slash (route
// matching strips it, `location.pathname` does not), so normalize before comparing.
const isOnBotsRoute = (): boolean =>
    stripTrailingSlash(removeProjectIdIfPresent(router.values.location.pathname)) === '/web/bots'

// Push the bot tab's filter state into the /web/bots URL. Only writes while the bots route is
// active; never touches the regular Analytics tab URL because `rawBotAnalyticsFilters` lives in
// a separate logic.
const syncBotFiltersToUrl = (
    rawBotAnalyticsFilters: WebAnalyticsPropertyFilters,
    dateFilter: DateFilterState
): void => {
    if (!isOnBotsRoute()) {
        return
    }
    const urlParams = new URLSearchParams(router.values.location.search)
    if (rawBotAnalyticsFilters.length > 0) {
        urlParams.set('filters', JSON.stringify(rawBotAnalyticsFilters))
    } else {
        urlParams.delete('filters')
    }
    // Always write the dates: a stale date param seeded from the current search would otherwise
    // survive and be re-applied by the urlToAction pass this replace triggers.
    const { dateFrom, dateTo, interval } = dateFilter
    urlParams.set('date_from', dateFrom ?? '')
    urlParams.set('date_to', dateTo ?? '')
    urlParams.set('interval', interval ?? '')
    router.actions.replace(`/web/bots${urlParams.toString() ? '?' + urlParams.toString() : ''}`)
}

