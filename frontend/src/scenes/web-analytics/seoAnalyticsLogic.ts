export type seoAnalyticsLogicType = MakeLogicType<
    seoAnalyticsLogicValues,
    seoAnalyticsLogicActions,
    Record<string, any>,
    seoAnalyticsLogicMeta
>

export const seoAnalyticsLogic = kea<seoAnalyticsLogicType>([
    path(['scenes', 'webAnalytics', 'seoAnalyticsLogic']),
    connect(() => ({
        values: [
            webAnalyticsLogic,
            ['dateFilter'],
            sourcesDataLogic,
            ['dataWarehouseSources', 'dataWarehouseSourcesLoading'],
        ],
        actions: [sourcesDataLogic, ['loadSources']],
    })),
    actions({
        setSeoTrendsTab: (tab: string) => ({ tab }),
    }),
    reducers({
        _seoTrendsTab: [
            null as string | null,
            {
                setSeoTrendsTab: (_, { tab }) => tab,
            },
        ],
    }),
    selectors(({ actions }) => ({
        seoTrendsTab: [(s) => [s._seoTrendsTab], (tab: string | null) => tab || 'clicks'],
        gscSource: [
            (s) => [s.dataWarehouseSources],
            (dataWarehouseSources: PaginatedResponse<ExternalDataSource> | null): ExternalDataSource | null =>
                dataWarehouseSources?.results?.find((source) => source.source_type === GSC_SOURCE_TYPE) ?? null,
        ],
        hasGscSource: [(s) => [s.gscSource], (gscSource: ExternalDataSource | null): boolean => !!gscSource],
        tiles: [
            (s) => [s.gscSource, s.dateFilter, s.seoTrendsTab],
            (
                gscSource: ExternalDataSource | null,
                dateFilter: DateFilterState,
                seoTrendsTab: string
            ): WebAnalyticsTile[] => {
                if (!gscSource) {
                    return []
                }

                const trendsTable = findSyncedTableName(gscSource, TRENDS_SCHEMA_CANDIDATES)
                const queriesTable = findSyncedTableName(gscSource, QUERIES_SCHEMA_CANDIDATES)
                const pagesTable = findSyncedTableName(gscSource, PAGES_SCHEMA_CANDIDATES)

                const dateRange = { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo }

                const createInsightProps = (tile: TileId, tab?: string): InsightLogicProps => ({
                    dashboardItemId: getDashboardItemId(tile, tab, false),
                    loadPriority: loadPriorityMap[tile],
                    dataNodeCollectionId: WEB_ANALYTICS_DATA_COLLECTION_NODE_ID,
                })

                const createSearchTrendsSeries = (
                    tableName: string,
                    mathHogql: string,
                    name: string
                ): DataWarehouseNode => ({
                    kind: NodeKind.DataWarehouseNode,
                    id: tableName,
                    name: tableName,
                    custom_name: name,
                    table_name: tableName,
                    id_field: 'date',
                    distinct_id_field: 'date',
                    timestamp_field: 'date',
                    math: HogQLMathType.HogQL,
                    math_hogql: mathHogql,
                })

                const createSearchTrendsTab = (
                    tableName: string,
                    id: string,
                    title: string,
                    mathHogql: string
                ): TabsTileTab => ({
                    id,
                    title,
                    linkText: title,
                    query: {
                        kind: NodeKind.InsightVizNode,
                        source: {
                            kind: NodeKind.TrendsQuery,
                            dateRange,
                            interval: dateFilter.interval ?? 'day',
                            series: [createSearchTrendsSeries(tableName, mathHogql, title)],
                            trendsFilter: {
                                display: ChartDisplayType.ActionsLineGraph,
                            } as TrendsFilter,
                            tags: WEB_ANALYTICS_DEFAULT_QUERY_TAGS,
                        },
                        hidePersonsModal: true,
                        embedded: true,
                    },
                    insightProps: createInsightProps(TileId.SEO_TRENDS, id),
                    canOpenInsight: true,
                    showIntervalSelect: true,
                })

                const createBreakdownTableTile = (
                    tileId: TileId,
                    title: string,
                    dimensionColumn: string,
                    dimensionLabel: string,
                    tableName: string
                ): WebAnalyticsTile => ({
                    kind: 'query',
                    tileId,
                    title,
                    layout: {
                        colSpanClassName: 'md:col-span-full',
                    },
                    query: {
                        full: true,
                        kind: NodeKind.DataTableNode,
                        source: {
                            kind: NodeKind.HogQLQuery,
                            query: searchAnalyticsBreakdownQuery(dimensionColumn, dimensionLabel, tableName),
                            filters: { dateRange },
                            tags: WEB_ANALYTICS_DEFAULT_QUERY_TAGS,
                        },
                        showActions: false,
                        embedded: true,
                    },
                    insightProps: createInsightProps(tileId, 'table'),
                    canOpenModal: false,
                    canOpenInsight: true,
                })

                const tiles: (WebAnalyticsTile | null)[] = [
                    trendsTable
                        ? {
                              kind: 'tabs',
                              tileId: TileId.SEO_TRENDS,
                              layout: {
                                  colSpanClassName: 'md:col-span-full',
                              },
                              activeTabId: seoTrendsTab,
                              setTabId: actions.setSeoTrendsTab,
                              tabs: [
                                  createSearchTrendsTab(trendsTable, 'clicks', 'Clicks', 'sum(clicks)'),
                                  createSearchTrendsTab(trendsTable, 'impressions', 'Impressions', 'sum(impressions)'),
                              ],
                          }
                        : null,
                    queriesTable
                        ? createBreakdownTableTile(TileId.SEO_QUERIES, 'Top queries', 'query', 'Query', queriesTable)
                        : null,
                    pagesTable
                        ? createBreakdownTableTile(TileId.SEO_PAGES, 'Top pages', 'page', 'Page', pagesTable)
                        : null,
                ]

                return tiles.filter((tile): tile is WebAnalyticsTile => tile !== null)
            },
        ],
    })),
    afterMount(({ actions, values }) => {
        if (!values.dataWarehouseSources && !values.dataWarehouseSourcesLoading) {
            actions.loadSources()
        }
    }),
])
