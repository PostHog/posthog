export const GSC_SOURCE_TYPE = 'GoogleSearchConsole'

// Base schema names from the Google Search Console source, in preference order per tile.
// `search_analytics_by_query_page` is the source's only default-on search analytics schema,
// so it doubles as the fallback for every tile.
const TRENDS_SCHEMA_CANDIDATES = [
    'search_analytics_by_date',
    'search_analytics_by_page',
    'search_analytics_by_query_page',
]
const QUERIES_SCHEMA_CANDIDATES = ['search_analytics_by_query', 'search_analytics_by_query_page']
const PAGES_SCHEMA_CANDIDATES = ['search_analytics_by_page', 'search_analytics_by_query_page']

const findSyncedTableName = (source: ExternalDataSource, schemaNames: string[]): string | null => {
    for (const schemaName of schemaNames) {
        const schema = source.schemas?.find((s) => s.name === schemaName && s.should_sync && s.table)
        if (schema?.table?.name) {
            return schema.table.name
        }
    }
    return null
}

// Aggregating position needs an impressions weighting: Search Console reports position
// per row, so a plain avg would let low-impression rows skew the number.
const searchAnalyticsBreakdownQuery = (dimensionColumn: string, dimensionLabel: string, tableName: string): string => `
SELECT
    ${dimensionColumn} AS \`${dimensionLabel}\`,
    sum(clicks) AS \`Clicks\`,
    sum(impressions) AS \`Impressions\`,
    round(sum(clicks) * 100.0 / nullif(sum(impressions), 0), 1) AS \`CTR\`,
    round(sum(position * impressions) / nullif(sum(impressions), 0), 1) AS \`Avg position\`
FROM ${tableName}
WHERE {filters(date AS timestamp)}
GROUP BY ${dimensionColumn}
ORDER BY \`Clicks\` DESC
LIMIT 100`

