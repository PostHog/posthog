import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { lemonToast } from '@posthog/lemon-ui'

import { objectsEqual } from 'lib/utils/objects'
import { addProductIntentForCrossSell } from 'lib/utils/product-intents'
import { insightsApi } from 'scenes/insights/utils/api'

import { ProductIntentContext, ProductKey, QuerySchema } from '~/queries/schema/schema-general'
import { QueryBasedInsightModel } from '~/types'

import type { Node } from '../../queries/schema/schema-general'
import { TileId, WebAnalyticsTile } from './common'
import { getNewInsightSourceFactory, webTileInsightName } from './insightsUtils'
import { webAnalyticsModalLogic } from './webAnalyticsModalLogic'

interface SaveTileAsInsightPayload {
    query: QuerySchema
    name: string
    /** Identifies the tile whose button shows the in-flight state. */
    tileKey: string
}

export const webTileKey = (tileId: TileId, tabId?: string): string => `${tileId}.${tabId ?? 'default'}`

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface webAnalyticsAddToDashboardLogicValues {
    combinedTiles: WebAnalyticsTile[] // webAnalyticsModalLogic
    isAddToDashboardModalOpen: boolean
    lastSavedQuery: QuerySchema | null
    savedInsight: QueryBasedInsightModel | null
    savedInsightLoading: boolean
    savingTileKey: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface webAnalyticsAddToDashboardLogicActions {
    addTileToDashboard: (
        tileId: TileId,
        tabId?: string
    ) => {
        tabId: string | undefined
        tileId: TileId
    }
    closeAddToDashboardModal: () => {
        value: true
    }
    openAddToDashboardModal: () => {
        value: true
    }
    saveTileAsInsight: ({ query, name }: SaveTileAsInsightPayload) => SaveTileAsInsightPayload
    saveTileAsInsightFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    saveTileAsInsightSuccess: (
        savedInsight: QueryBasedInsightModel<Node<Record<string, any>>>,
        payload?: SaveTileAsInsightPayload
    ) => {
        savedInsight: QueryBasedInsightModel<Node<Record<string, any>>>
        payload?: SaveTileAsInsightPayload
    }
}

export type webAnalyticsAddToDashboardLogicType = MakeLogicType<
    webAnalyticsAddToDashboardLogicValues,
    webAnalyticsAddToDashboardLogicActions
>

/**
 * Puts a web analytics tile on a dashboard: it saves the tile query as an insight, then opens the
 * standard picker so the user chooses the dashboard. Web analytics tiles are not insights, and
 * `addToDashboardModalLogic` only patches an insight that already exists.
 */
export const webAnalyticsAddToDashboardLogic = kea<webAnalyticsAddToDashboardLogicType>([
    path(['scenes', 'webAnalytics', 'webAnalyticsAddToDashboardLogic']),

    connect(() => ({
        values: [webAnalyticsModalLogic, ['combinedTiles']],
    })),

    actions({
        addTileToDashboard: (tileId: TileId, tabId?: string) => ({ tileId, tabId }),
        openAddToDashboardModal: true,
        closeAddToDashboardModal: true,
    }),

    loaders({
        savedInsight: [
            null as QueryBasedInsightModel | null,
            {
                saveTileAsInsight: async ({ query, name }: SaveTileAsInsightPayload) =>
                    await insightsApi.create({ name, query, saved: true }),
            },
        ],
    }),

    reducers({
        isAddToDashboardModalOpen: [
            false,
            {
                openAddToDashboardModal: () => true,
                closeAddToDashboardModal: () => false,
            },
        ],
        // The query the last successful save sent. The reuse check compares against this, not
        // against the server-returned insight.query, because the API normalizes the stored node
        // and a comparison against that would save a duplicate insight on every click.
        lastSavedQuery: [
            null as QuerySchema | null,
            {
                saveTileAsInsightSuccess: (state, { payload }) => payload?.query ?? state,
            },
        ],
        savingTileKey: [
            null as string | null,
            {
                saveTileAsInsight: (_, { tileKey }) => tileKey,
                saveTileAsInsightSuccess: () => null,
                saveTileAsInsightFailure: () => null,
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        addTileToDashboard: ({ tileId, tabId }) => {
            const source = getNewInsightSourceFactory(values.combinedTiles)(tileId, tabId)
            if (!source) {
                return
            }

            posthog.capture('web analytics tile add to dashboard clicked', { tile_id: tileId, tab_id: tabId })
            void addProductIntentForCrossSell({
                from: ProductKey.WEB_ANALYTICS,
                to: ProductKey.PRODUCT_ANALYTICS,
                intent_context: ProductIntentContext.WEB_ANALYTICS_INSIGHT,
            })

            // Re-clicking with an unchanged query reuses the saved insight instead of littering
            // saved insights with duplicates.
            if (values.savedInsight && objectsEqual(values.lastSavedQuery, source.query)) {
                actions.openAddToDashboardModal()
                return
            }

            actions.saveTileAsInsight({
                query: source.query,
                name: webTileInsightName(source.title),
                tileKey: webTileKey(tileId, tabId),
            })
        },
        saveTileAsInsightSuccess: ({ savedInsight }) => {
            if (savedInsight) {
                actions.openAddToDashboardModal()
            }
        },
        saveTileAsInsightFailure: ({ error }) => {
            lemonToast.error(`Could not save this tile as an insight: ${error}`)
        },
    })),
])
