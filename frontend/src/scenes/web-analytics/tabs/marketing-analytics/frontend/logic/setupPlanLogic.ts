export type SuggestionSeverity = 'error' | 'warning' | 'info'
export type SuggestionSource = 'deterministic' | 'ai'
export type ReadinessStatus = 'unlocked' | 'partial' | 'blocked'

/** Ops whose writes change what the UTM audit reports. The audit reruns the campaign
 * and UTM-catalogue queries the setup plan just ran, so reloading it for a goal change
 * pays twice for a scan that can't have moved. */
const AUDIT_AFFECTING_OPS = new Set([
    'add_custom_source_mapping',
    'remove_custom_source_mapping',
    'add_campaign_name_mapping',
    'remove_campaign_name_mapping',
    'set_campaign_field_preference',
])

const teamId = window.POSTHOG_APP_CONTEXT?.current_team?.id
/** Suggestion ids are semantic and project-independent — `connect_source:google_ads`
 * is the same string in every project — so an unprefixed bucket would hide a finding
 * in one project because it was dismissed in another. Matches marketingAnalyticsLogic. */
const persistConfig = { persist: true, prefix: `${teamId}__` }

export type Capability = 'cost' | 'attribution' | 'roas' | 'cac'

/** Recorded server-side against the change, so it must describe the real origin. */
export type ApplySource = 'setup_tab' | 'apply_all_safe'

/** Mirrors the `ApplyOp` union in `services/setup_types.py`. Passed back to
 * apply_setup_ops verbatim — never construct one client-side. */
export interface ApplyOp {
    op: string
    [key: string]: unknown
}

/** The serializer's shape, with the fields it can only describe as `string` or
 * `unknown` narrowed to what the backend actually puts in them. Built on the generated
 * type rather than restated, so a field the backend renames or drops fails to compile
 * here instead of arriving as undefined at runtime. */
export type Suggestion = Omit<SuggestionApi, 'source' | 'severity' | 'unlocks' | 'apply' | 'also_recommended'> & {
    source: SuggestionSource
    severity: SuggestionSeverity
    unlocks: Capability[]
    apply: ApplyOp | null
    also_recommended: ApplyOp[]
}

/** One warehouse source to re-sync. Mirrors `SyncTarget` in `setup_types.py`. */
export interface SyncTarget {
    source_id: string
    display_name: string
}

export type CapabilityReadiness = Omit<CapabilityReadinessApi, 'capability' | 'status'> & {
    capability: Capability
    status: ReadinessStatus
}

export type SetupPlanResponse = Omit<SetupPlanResponseApi, 'suggestions' | 'readiness'> & {
    suggestions: Suggestion[]
    readiness: CapabilityReadiness[]
}

interface ApplyResponse {
    applied: ApplyOp[]
    undo_ops: ApplyOp[]
}

