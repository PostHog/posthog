export const setupPlanLogic = kea<setupPlanLogicType>([
    path(['scenes', 'web-analytics', 'tabs', 'marketing-analytics', 'frontend', 'logic', 'setupPlanLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
        actions: [
            teamLogic,
            ['loadCurrentTeam'],
            marketingAnalyticsSettingsLogic,
            ['loadMarketingAnalyticsConfig'],
            utmAuditLogic,
            ['loadAuditData'],
        ],
    })),
    actions({
        applySuggestion: (suggestion: Suggestion) => ({ suggestion }),
        applyAllSafe: true,
        applyOps: (
            ops: ApplyOp[],
            options: { label: string; source: ApplySource; undoable?: boolean; suggestionIds?: string[] }
        ) => ({
            ops,
            options,
        }),
        setApplying: (ids: string[], applying: boolean) => ({ ids, applying }),
        markApplied: (ids: string[]) => ({ ids }),
        dismissSuggestion: (id: string) => ({ id }),
        /** Put a dismissed suggestion back. Dismissing was a one-way door: the count
         * was shown with no way to see what was behind it, while the tooltip claimed
         * the row was "hidden until you clear it" with nothing able to clear it. */
        restoreSuggestion: (id: string) => ({ id }),
        restoreAllDismissed: true,
        toggleShowDismissed: true,
        /** Kick off one or more warehouse syncs. A list rather than a single source so
         * the collapsed "5 platforms are stale" row can retry the group in one click,
         * with N=1 as the ordinary case rather than a separate path. */
        retrySync: (suggestionId: string, targets: SyncTarget[]) => ({ suggestionId, targets }),
        /** Open the review modal for a suggestion, or close it with null. Every action
         * goes through review — a preview costs one click and buys the user the
         * ability to disagree before their config changes. */
        reviewSuggestion: (suggestion: Suggestion | null) => ({ suggestion }),
        /** Review the whole safe batch at once. Same modal, so "apply all" can't be
         * the one action that changes config without showing what it changes. */
        reviewSafeBatch: true,
        confirmReviewedSuggestion: (suggestion: Suggestion) => ({ suggestion }),
        confirmReviewedBatch: (suggestions: Suggestion[]) => ({ suggestions }),
        /** Narrow the list to what unblocks one capability, or null for everything.
         * The readiness chips are the only entry point: "ROAS is locked" is a useless
         * fact unless the next click is "so show me what unlocks it". */
        focusCapability: (capability: Capability | null) => ({ capability }),
    }),
    loaders(({ values }) => ({
        setupPlan: [
            null as SetupPlanResponse | null,
            {
                /** `refresh` forces a fresh scan past the server's short cache.
                 *
                 * The mount-time load is happy with a cached plan — that's the whole
                 * point of the cache, so switching sections doesn't re-run six
                 * ClickHouse queries. An explicit Rescan click is a request for
                 * current data and has to mean it, or the button looks broken. */
                loadSetupPlan: async ({ refresh } = { refresh: false }) => {
                    const response = await api.get(
                        `api/projects/${values.currentTeamId}/marketing_analytics/setup_plan${
                            refresh ? '?refresh=true' : ''
                        }`
                    )
                    return response as SetupPlanResponse
                },
            },
        ],
    })),
    reducers({
        applyingIds: [
            [] as string[],
            {
                setApplying: (state, { ids, applying }) =>
                    applying ? [...new Set([...state, ...ids])] : state.filter((id) => !ids.includes(id)),
            },
        ],
        // Collapse a row the moment its op succeeds, so the list reflects the click
        // before the plan has finished reloading. Cleared on every reload — the
        // server's view of what's still outstanding wins.
        locallyAppliedIds: [
            [] as string[],
            {
                markApplied: (state, { ids }) => [...new Set([...state, ...ids])],
                loadSetupPlanSuccess: () => [],
            },
        ],
        reviewingSuggestion: [
            null as Suggestion | null,
            {
                reviewSuggestion: (_, { suggestion }) => suggestion,
                reviewSafeBatch: () => null,
                // `markApplied`, not `loadSetupPlanSuccess`: the reload runs in the
                // listener's `finally` and succeeds even when the apply didn't, so keying
                // off it closed the modal on failure — the opposite of the intent. This
                // only fires inside the `try`, so a failed apply keeps the modal open with
                // its error rather than vanishing.
                markApplied: () => null,
            },
        ],
        isReviewingBatch: [
            false,
            {
                reviewSafeBatch: () => true,
                reviewSuggestion: () => false,
                markApplied: () => false,
            },
        ],
        dismissedIds: [
            [] as string[],
            persistConfig,
            {
                dismissSuggestion: (state, { id }) => [...new Set([...state, id])],
                restoreSuggestion: (state, { id }) => state.filter((dismissed: string) => dismissed !== id),
                restoreAllDismissed: () => [],
            },
        ],
        showDismissed: [
            false,
            {
                toggleShowDismissed: (state) => !state,
                // Nothing left to look at once they're all back.
                restoreAllDismissed: () => false,
            },
        ],
        focusedCapability: [
            null as Capability | null,
            {
                // Toggle: clicking the chip you're already filtered by clears it, so the
                // chip is both the way in and the way out.
                focusCapability: (state, { capability }) => (state === capability ? null : capability),
                // A rescan can change which capabilities exist at all; holding a filter
                // across it risks an empty list with no visible cause.
                loadSetupPlanSuccess: () => null,
            },
        ],
    }),
    selectors({
        suggestions: [(s) => [s.setupPlan], (plan: SetupPlanResponse | null): Suggestion[] => plan?.suggestions ?? []],
        readiness: [
            (s) => [s.setupPlan],
            (plan: SetupPlanResponse | null): CapabilityReadiness[] => plan?.readiness ?? [],
        ],
        degraded: [(s) => [s.setupPlan], (plan: SetupPlanResponse | null): string[] => plan?.degraded ?? []],
        truncated: [(s) => [s.setupPlan], (plan: SetupPlanResponse | null): boolean => plan?.truncated ?? false],
        visibleSuggestions: [
            (s) => [s.suggestions, s.dismissedIds, s.locallyAppliedIds],
            (suggestions: Suggestion[], dismissedIds: string[], locallyAppliedIds: string[]): Suggestion[] =>
                suggestions.filter(
                    (suggestion: Suggestion) =>
                        !dismissedIds.includes(suggestion.id) && !locallyAppliedIds.includes(suggestion.id)
                ),
        ],
        // AI-sourced suggestions are never batchable server-side, so this is
        // deterministic-only by construction rather than by an extra filter here.
        safeBatch: [
            (s) => [s.visibleSuggestions],
            (suggestions: Suggestion[]): Suggestion[] =>
                suggestions.filter((suggestion: Suggestion) => suggestion.safe_to_batch && suggestion.apply),
        ],
        appliedCount: [
            (s) => [s.suggestions, s.visibleSuggestions],
            (all: Suggestion[], visible: Suggestion[]): number => all.length - visible.length,
        ],
        /** The dismissed rows the current plan still reports.
         *
         * Intersected with the plan rather than read straight off `dismissedIds`,
         * because that list is persisted and its ids outlive the findings: dismiss a
         * broken sync, fix the sync, and the id stays in localStorage forever. Counting
         * it would advertise hidden work that no longer exists and can't be shown.
         */
        dismissedSuggestions: [
            (s) => [s.suggestions, s.dismissedIds],
            (suggestions: Suggestion[], dismissedIds: string[]): Suggestion[] =>
                suggestions.filter((suggestion: Suggestion) => dismissedIds.includes(suggestion.id)),
        ],
        /** What the ranked list renders. Separate from `visibleSuggestions` because the
         * per-section blocks and the nav badges must keep showing everything — a filter
         * chosen in "Suggested setup" silently emptying the Sources section would read
         * as a bug, not as a filter. */
        listedSuggestions: [
            (s) => [s.visibleSuggestions, s.focusedCapability],
            (suggestions: Suggestion[], capability: Capability | null): Suggestion[] =>
                capability
                    ? suggestions.filter((suggestion: Suggestion) => suggestion.unlocks.includes(capability))
                    : suggestions,
        ],
    }),
    listeners(({ actions, values }) => ({
        retrySync: async ({ suggestionId, targets }) => {
            // Goes straight to the warehouse endpoint rather than through
            // apply_setup_ops: the warehouse owns this action and its permissions, and
            // the apply endpoint only mutates marketing config.
            actions.setApplying([suggestionId], true)
            try {
                // Sequential, and one failure does not abandon the rest: these are
                // independent sources, and stopping at the first error would leave the
                // group half-retried with no way to tell which half.
                const failed: string[] = []
                for (const target of targets) {
                    try {
                        await api.externalDataSources.reload(target.source_id)
                    } catch {
                        failed.push(target.display_name)
                    }
                }
                if (failed.length === targets.length) {
                    lemonToast.error(`Could not retry ${failed.join(', ')}.`)
                } else if (failed.length) {
                    lemonToast.warning(
                        `Retrying ${targets.length - failed.length} of ${targets.length}. Failed: ${failed.join(', ')}.`
                    )
                } else {
                    lemonToast.success(
                        targets.length === 1
                            ? `Retrying the ${targets[0].display_name} sync`
                            : `Retrying ${targets.length} syncs`
                    )
                }
            } finally {
                actions.setApplying([suggestionId], false)
                actions.reviewSuggestion(null)
                // A sync takes minutes, so the plan won't change yet — reload anyway so
                // a status that did change (a second click after it finished) is picked up.
                actions.loadSetupPlan()
            }
        },
        confirmReviewedSuggestion: ({ suggestion }) => {
            // Navigation is handled by the view (see `runNavigateOp`), which owns the
            // router and the modals. This only knows how to change config and to kick
            // off a sync.
            if (suggestion.apply?.op === 'retry_sync') {
                actions.retrySync(suggestion.id, [
                    {
                        source_id: suggestion.apply.source_id as string,
                        display_name: suggestion.apply.display_name as string,
                    },
                ])
                return
            }
            if (suggestion.apply?.op === 'retry_syncs') {
                actions.retrySync(suggestion.id, suggestion.apply.sources as SyncTarget[])
                return
            }
            actions.applySuggestion(suggestion)
        },
        applySuggestion: ({ suggestion }) => {
            if (!suggestion.apply) {
                return
            }
            actions.setApplying([suggestion.id], true)
            actions.applyOps([suggestion.apply], {
                label: suggestion.title,
                source: 'setup_tab',
                undoable: true,
                suggestionIds: [suggestion.id],
            })
        },
        confirmReviewedBatch: ({ suggestions }) => {
            if (!suggestions.length) {
                return
            }
            actions.setApplying(
                suggestions.map((s) => s.id),
                true
            )
            actions.applyOps(
                suggestions.map((s) => s.apply as ApplyOp),
                {
                    label: `Applied ${suggestions.length} suggestion${suggestions.length === 1 ? '' : 's'}`,
                    source: 'apply_all_safe',
                    undoable: true,
                    suggestionIds: suggestions.map((s) => s.id),
                }
            )
        },
        applyAllSafe: () => {
            const batch = values.safeBatch
            if (!batch.length) {
                return
            }
            actions.setApplying(
                batch.map((s) => s.id),
                true
            )
            actions.applyOps(
                batch.map((s) => s.apply as ApplyOp),
                {
                    label: `Applied ${batch.length} suggestion${batch.length === 1 ? '' : 's'}`,
                    source: 'apply_all_safe',
                    undoable: true,
                    suggestionIds: batch.map((s) => s.id),
                }
            )
        },
        applyOps: async ({ ops, options }) => {
            // The rows this request owns, not whatever happens to be applying. Reading
            // the global set meant an undo — which starts no rows of its own — would
            // adopt a concurrent apply's ids and mark those rows applied when it landed.
            const inFlight = options.suggestionIds ?? []
            try {
                const response: ApplyResponse = await api.create(
                    `api/projects/${values.currentTeamId}/marketing_analytics/apply_setup_ops`,
                    { ops, source: options.source }
                )

                actions.markApplied(inFlight)
                lemonToast.success(options.label, {
                    button:
                        options.undoable && response.undo_ops.length
                            ? {
                                  label: 'Undo',
                                  // The server computes the inverse from the pre-change
                                  // state, so undo is just another apply — the client
                                  // never reconstructs what the config used to be.
                                  action: () =>
                                      actions.applyOps(response.undo_ops, {
                                          label: 'Undone',
                                          source: options.source,
                                      }),
                              }
                            : undefined,
                })
            } catch (error: any) {
                lemonToast.error(error?.detail ?? 'Could not apply that change.')
            } finally {
                actions.setApplying(inFlight, false)
                actions.loadSetupPlan()
                // apply_setup_ops writes the config server-side, bypassing
                // `updateCurrentTeam`. Nothing else would know: the manual settings
                // sections below read `savedMarketingAnalyticsConfig`, which keys off
                // that action, and utmAuditLogic only reloads on the update*Mappings
                // actions. Without these the manual sections show stale data right next
                // to the suggestion that just changed it.
                //
                // Awaited, not fire-and-forget: `loadMarketingAnalyticsConfig` reads
                // `values.currentTeam` synchronously, so dispatching it in the same tick
                // reads the pre-apply team every time.
                await teamLogic.asyncActions.loadCurrentTeam()
                actions.loadMarketingAnalyticsConfig()
                // Only for ops that touch what the audit reports on. It reruns the same
                // UTM-catalogue and campaign-spend ClickHouse queries the plan just ran,
                // so a conversion-goal change would pay for a scan it can't affect.
                if (ops.some((candidate) => AUDIT_AFFECTING_OPS.has(candidate.op))) {
                    actions.loadAuditData()
                }
            }
        },
    })),
])
