import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'

import {
    ConversionGoalFilter,
    type MarketingAnalyticsConfig,
    MarketingAnalyticsAttributionBreakdown,
    MarketingAnalyticsAttributionQuery,
    NodeKind,
} from '~/queries/schema/schema-general'
import { IntervalType } from '~/types'

import { marketingAnalyticsLogic } from './marketingAnalyticsLogic'
import { marketingAnalyticsSettingsLogic } from './marketingAnalyticsSettingsLogic'

/** Rows the table asks for. Sorting happens client side over this page, so it's also the sort scope. */
export const ATTRIBUTION_ROW_LIMIT = 100

export const DEFAULT_ATTRIBUTION_WINDOW_DAYS = 90

export const BREAKDOWN_LABELS: Record<MarketingAnalyticsAttributionBreakdown, string> = {
    [MarketingAnalyticsAttributionBreakdown.Channel]: 'Channel',
    [MarketingAnalyticsAttributionBreakdown.Source]: 'Source',
    [MarketingAnalyticsAttributionBreakdown.Campaign]: 'Campaign',
    [MarketingAnalyticsAttributionBreakdown.Medium]: 'Medium',
    [MarketingAnalyticsAttributionBreakdown.Content]: 'Content',
    [MarketingAnalyticsAttributionBreakdown.Term]: 'Term',
    [MarketingAnalyticsAttributionBreakdown.ReferringDomain]: 'Referring domain',
    [MarketingAnalyticsAttributionBreakdown.LandingPage]: 'Landing page',
}

interface DateFilter {
    dateFrom: string | null
    dateTo: string | null
    interval: IntervalType
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface marketingAttributionLogicValues {
    dateFilter: DateFilter // marketingAnalyticsLogic
    conversion_goals: ConversionGoalFilter[] // marketingAnalyticsSettingsLogic
    marketingAnalyticsConfig: MarketingAnalyticsConfig | null // marketingAnalyticsSettingsLogic
    attributableGoals: ConversionGoalFilter[]
    attributionWindowDays: number
    breakdownBy: MarketingAnalyticsAttributionBreakdown
    conversionGoalId: string | null
    excludeDirectTraffic: boolean
    query: MarketingAnalyticsAttributionQuery | null
    selectedGoalId: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface marketingAttributionLogicActions {
    setBreakdownBy: (breakdownBy: MarketingAnalyticsAttributionBreakdown) => {
        breakdownBy: MarketingAnalyticsAttributionBreakdown
    }
    setConversionGoalId: (conversionGoalId: string) => { conversionGoalId: string }
    setExcludeDirectTraffic: (excludeDirectTraffic: boolean) => { excludeDirectTraffic: boolean }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface marketingAttributionLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        attributableGoals: (conversion_goals: ConversionGoalFilter[]) => ConversionGoalFilter[]
        selectedGoalId: (conversionGoalId: string | null, attributableGoals: ConversionGoalFilter[]) => string | null
        attributionWindowDays: (marketingAnalyticsConfig: MarketingAnalyticsConfig | null) => number
        query: (
            selectedGoalId: string | null,
            breakdownBy: MarketingAnalyticsAttributionBreakdown,
            excludeDirectTraffic: boolean,
            dateFilter: DateFilter
        ) => MarketingAnalyticsAttributionQuery | null
    }
}

export type marketingAttributionLogicType = MakeLogicType<
    marketingAttributionLogicValues,
    marketingAttributionLogicActions,
    Record<string, any>,
    marketingAttributionLogicMeta
>

export const marketingAttributionLogic = kea<marketingAttributionLogicType>([
    path(['scenes', 'webAnalytics', 'marketingAttributionLogic']),
    connect(() => ({
        values: [
            // The tab renders under the scene's shared filter bar, so it reuses that date range rather
            // than owning a second date control the user would have to keep in sync.
            marketingAnalyticsLogic,
            ['dateFilter'],
            marketingAnalyticsSettingsLogic,
            ['conversion_goals', 'marketingAnalyticsConfig'],
        ],
    })),
    actions({
        setBreakdownBy: (breakdownBy: MarketingAnalyticsAttributionBreakdown) => ({ breakdownBy }),
        setConversionGoalId: (conversionGoalId: string) => ({ conversionGoalId }),
        setExcludeDirectTraffic: (excludeDirectTraffic: boolean) => ({ excludeDirectTraffic }),
    }),
    reducers({
        breakdownBy: [
            MarketingAnalyticsAttributionBreakdown.Channel as MarketingAnalyticsAttributionBreakdown,
            { setBreakdownBy: (_, { breakdownBy }) => breakdownBy },
        ],
        conversionGoalId: [
            null as string | null,
            { setConversionGoalId: (_, { conversionGoalId }) => conversionGoalId },
        ],
        excludeDirectTraffic: [
            false,
            { setExcludeDirectTraffic: (_, { excludeDirectTraffic }) => excludeDirectTraffic },
        ],
    }),
    selectors({
        attributableGoals: [
            (s) => [s.conversion_goals],
            // Data warehouse goals are excluded: their conversions live in a warehouse table keyed by
            // distinct id, so the events-based touchpoint query has nothing to join them on.
            (conversion_goals): ConversionGoalFilter[] =>
                (conversion_goals || []).filter((goal) => goal.kind !== NodeKind.DataWarehouseNode),
        ],
        selectedGoalId: [
            (s) => [s.conversionGoalId, s.attributableGoals],
            (conversionGoalId, attributableGoals): string | null => {
                const stillAvailable = attributableGoals.some((goal) => goal.conversion_goal_id === conversionGoalId)
                if (conversionGoalId && stillAvailable) {
                    return conversionGoalId
                }
                return attributableGoals[0]?.conversion_goal_id ?? null
            },
        ],
        attributionWindowDays: [
            (s) => [s.marketingAnalyticsConfig],
            (marketingAnalyticsConfig): number =>
                marketingAnalyticsConfig?.attribution_window_days ?? DEFAULT_ATTRIBUTION_WINDOW_DAYS,
        ],
        query: [
            (s) => [s.selectedGoalId, s.breakdownBy, s.excludeDirectTraffic, s.dateFilter],
            (
                selectedGoalId,
                breakdownBy,
                excludeDirectTraffic,
                dateFilter
            ): MarketingAnalyticsAttributionQuery | null => {
                if (!selectedGoalId) {
                    return null
                }
                return {
                    kind: NodeKind.MarketingAnalyticsAttributionQuery,
                    dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo },
                    breakdownBy,
                    conversionGoalId: selectedGoalId,
                    excludeDirectTraffic,
                    limit: ATTRIBUTION_ROW_LIMIT,
                    properties: [],
                }
            },
        ],
    }),
])
