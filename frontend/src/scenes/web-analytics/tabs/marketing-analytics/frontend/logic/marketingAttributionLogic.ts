export const marketingAttributionLogic = kea<marketingAttributionLogicType>([
    path(['scenes', 'webAnalytics', 'marketingAttributionLogic']),
    connect(() => ({
        values: [
            // The tab renders under the scene's shared filter bar, so it reuses that date range rather
            // than owning a second date control the user would have to keep in sync.
            marketingAnalyticsLogic,
            ['dateFilter'],
            marketingAnalyticsSettingsLogic,
            ['conversion_goals', 'attribution_window_days'],
        ],
    })),
    actions({
        setBreakdownBy: (breakdownBy: MarketingAnalyticsAttributionBreakdown) => ({ breakdownBy }),
        setConversionGoalId: (conversionGoalId: string) => ({ conversionGoalId }),
        setExcludeDirectTraffic: (excludeDirectTraffic: boolean) => ({ excludeDirectTraffic }),
        setExcludeUnattributed: (excludeUnattributed: boolean) => ({ excludeUnattributed }),
        setLookbackWindowDays: (lookbackWindowDays: number | null) => ({ lookbackWindowDays }),
        setPathTouchpointFilter: (pathTouchpointFilter: PathTouchpointFilter) => ({ pathTouchpointFilter }),
        setAllowMultipleConversionsPerVisitor: (allowMultipleConversionsPerVisitor: boolean) => ({
            allowMultipleConversionsPerVisitor,
        }),
        setOptionsOpen: (optionsOpen: boolean) => ({ optionsOpen }),
    }),
    reducers({
        breakdownBy: [
            MarketingAnalyticsAttributionBreakdown.Channel as MarketingAnalyticsAttributionBreakdown,
            { setBreakdownBy: (_, { breakdownBy }) => breakdownBy },
        ],
        conversionGoalId: [
            null as string | null,
            { setConversionGoalId: (_, { conversionGoalId }) => conversionGoalId },
        ],
        excludeDirectTraffic: [
            false,
            { setExcludeDirectTraffic: (_, { excludeDirectTraffic }) => excludeDirectTraffic },
        ],
        excludeUnattributed: [false, { setExcludeUnattributed: (_, { excludeUnattributed }) => excludeUnattributed }],
        // null means "any number of touchpoints".
        pathTouchpointFilter: [
            null as PathTouchpointFilter,
            { setPathTouchpointFilter: (_, { pathTouchpointFilter }) => pathTouchpointFilter },
        ],
        // null means "use the team's configured window", so a later settings change flows through.
        lookbackWindowDays: [
            null as number | null,
            { setLookbackWindowDays: (_, { lookbackWindowDays }) => lookbackWindowDays },
        ],
        optionsOpen: [false, { setOptionsOpen: (_, { optionsOpen }) => optionsOpen }],
        // null means "follow the goal's own math", so a unique-users goal dedupes without being asked.
        allowMultipleConversionsPerVisitor: [
            null as boolean | null,
            {
                setAllowMultipleConversionsPerVisitor: (_, { allowMultipleConversionsPerVisitor }) =>
                    allowMultipleConversionsPerVisitor,
                // A different goal brings different math, so an override chosen for the old one shouldn't stick.
                setConversionGoalId: () => null,
            },
        ],
    }),
    selectors({
        attributableGoals: [
            (s) => [s.conversion_goals],
            // Data warehouse goals are excluded: their conversions live in a warehouse table keyed by
            // distinct id, so the events-based touchpoint query has nothing to join them on.
            (conversion_goals: ConversionGoalFilter[]): ConversionGoalFilter[] =>
                (conversion_goals || []).filter((goal) => goal.kind !== NodeKind.DataWarehouseNode),
        ],
        selectedGoalId: [
            (s) => [s.conversionGoalId, s.attributableGoals],
            (conversionGoalId: string | null, attributableGoals: ConversionGoalFilter[]): string | null => {
                const stillAvailable = attributableGoals.some((goal) => goal.conversion_goal_id === conversionGoalId)
                if (conversionGoalId && stillAvailable) {
                    return conversionGoalId
                }
                return attributableGoals[0]?.conversion_goal_id ?? null
            },
        ],
        effectiveLookbackDays: [
            (s) => [s.lookbackWindowDays, s.attribution_window_days],
            (lookbackWindowDays: number | null, attribution_window_days: number): number =>
                lookbackWindowDays ?? attribution_window_days,
        ],
        effectiveAllowMultipleConversions: [
            (s) => [s.allowMultipleConversionsPerVisitor, s.selectedGoalId, s.attributableGoals],
            // Mirrors the runner's default so the checkbox shows what the query will actually do: a
            // unique-users goal already counts each person once, anything else counts every conversion.
            (
                allowMultipleConversionsPerVisitor: boolean | null,
                selectedGoalId: string | null,
                attributableGoals: ConversionGoalFilter[]
            ): boolean => {
                if (allowMultipleConversionsPerVisitor !== null) {
                    return allowMultipleConversionsPerVisitor
                }
                const goal = attributableGoals.find((g) => g.conversion_goal_id === selectedGoalId)
                return goal?.math !== BaseMathType.UniqueUsers
            },
        ],
        query: [
            (s) => [
                s.selectedGoalId,
                s.breakdownBy,
                s.excludeDirectTraffic,
                s.excludeUnattributed,
                s.lookbackWindowDays,
                s.allowMultipleConversionsPerVisitor,
                s.dateFilter,
            ],
            (
                selectedGoalId: string | null,
                breakdownBy: MarketingAnalyticsAttributionBreakdown,
                excludeDirectTraffic: boolean,
                excludeUnattributed: boolean,
                lookbackWindowDays: number | null,
                allowMultipleConversionsPerVisitor: boolean | null,
                dateFilter: DateFilter
            ): MarketingAnalyticsAttributionQuery | null => {
                if (!selectedGoalId) {
                    return null
                }
                return {
                    kind: NodeKind.MarketingAnalyticsAttributionQuery,
                    dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo },
                    breakdownBy,
                    conversionGoalId: selectedGoalId,
                    excludeDirectTraffic,
                    excludeUnattributed,
                    ...(lookbackWindowDays ? { lookbackWindowDays } : {}),
                    // Omitted when null so the backend applies the goal's own math.
                    ...(allowMultipleConversionsPerVisitor !== null ? { allowMultipleConversionsPerVisitor } : {}),
                    limit: ATTRIBUTION_ROW_LIMIT,
                    properties: [],
                }
            },
        ],
        pathsQuery: [
            (s) => [s.query, s.pathTouchpointFilter],
            // Derived from the table's query so the two sections can never disagree on goal, breakdown,
            // window or exclusions; only the kind, the length filter and the row limit differ.
            (
                query: MarketingAnalyticsAttributionQuery | null,
                pathTouchpointFilter: PathTouchpointFilter
            ): MarketingAnalyticsAttributionPathsQuery | null => {
                if (!query) {
                    return null
                }
                return {
                    kind: NodeKind.MarketingAnalyticsAttributionPathsQuery,
                    dateRange: query.dateRange,
                    breakdownBy: query.breakdownBy,
                    conversionGoalId: query.conversionGoalId,
                    excludeDirectTraffic: query.excludeDirectTraffic,
                    excludeUnattributed: query.excludeUnattributed,
                    ...(query.lookbackWindowDays ? { lookbackWindowDays: query.lookbackWindowDays } : {}),
                    ...(query.allowMultipleConversionsPerVisitor !== undefined
                        ? { allowMultipleConversionsPerVisitor: query.allowMultipleConversionsPerVisitor }
                        : {}),
                    ...(pathTouchpointFilter === 'four_plus'
                        ? { minTouchpoints: 4 }
                        : pathTouchpointFilter !== null
                          ? { minTouchpoints: pathTouchpointFilter, maxTouchpoints: pathTouchpointFilter }
                          : {}),
                    limit: PATHS_ROW_LIMIT,
                    properties: [],
                }
            },
        ],
    }),
])
