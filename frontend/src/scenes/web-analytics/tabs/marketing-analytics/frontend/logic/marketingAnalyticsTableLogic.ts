export const marketingAnalyticsTableLogic = kea<marketingAnalyticsTableLogicType>([
    path(['scenes', 'marketingAnalytics', 'marketingAnalyticsTableLogic']),
    connect(() => ({
        values: [
            marketingAnalyticsLogic,
            ['conversion_goals', 'draftConversionGoal', 'drillDownLevel'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [marketingAnalyticsLogic, ['setDraftConversionGoal']],
    })),
    actions({
        setQuery: (query: DataTableNode) => ({ query }),
        setColumnConfiguration: (columnConfiguration: ColumnConfiguration) => ({ columnConfiguration }),
    }),
    reducers(() => ({
        columnConfiguration: [
            null as ColumnConfiguration | null,
            buildTeamScopedPersistenceConfig(),
            {
                setColumnConfiguration: (_, { columnConfiguration }) => columnConfiguration,
            },
        ],
        _query: [
            null as DataTableNode | null,
            {
                setQuery: (_, { query }) => query,
            },
        ],
    })),
    selectors({
        query: [
            (s) => [s._query, s.columnConfiguration],
            (query: DataTableNode | null, columnConfiguration: ColumnConfiguration | null): DataTableNode | null =>
                query ??
                (columnConfiguration
                    ? {
                          kind: NodeKind.DataTableNode,
                          pinnedColumns: columnConfiguration.pinnedColumns,
                          source: {
                              kind: NodeKind.MarketingAnalyticsTableQuery,
                              properties: [],
                              select: columnConfiguration.select,
                              orderBy: columnConfiguration.orderBy,
                          },
                      }
                    : null),
        ],
        defaultColumns: [
            (s) => [s.conversion_goals, s.drillDownLevel, s.featureFlags],
            (
                conversionGoals: ConversionGoalFilter[],
                drillDownLevel: MarketingAnalyticsDrillDownLevel,
                featureFlags: FeatureFlagsSet
            ) => {
                const config = MARKETING_ANALYTICS_DRILL_DOWN_CONFIG[drillDownLevel]
                // Hierarchy columns are auto-excluded outside AD_GROUP / AD — see
                // getEffectiveExcludedColumns. Routing on the user-config (config.excludedBaseColumns)
                // keeps CAMPAIGN on the natural-order path (preserves master's [ID, Campaign, Source, …]).
                const effectiveExcluded = getEffectiveExcludedColumns(drillDownLevel)

                // Dedupe in case the alias also appears in the filtered base columns
                // (e.g. AD_GROUP / AD where the alias matches a base column that isn't
                // excluded). Without this we'd render the primary column twice and
                // confuse the URL/order machinery.
                const baseColumns =
                    config.excludedBaseColumns.length > 0
                        ? Array.from(
                              new Set([
                                  config.columnAlias,
                                  ...Object.values(MarketingAnalyticsBaseColumns).filter(
                                      (col) => !effectiveExcluded.has(col)
                                  ),
                              ])
                          )
                        : Object.values(MarketingAnalyticsBaseColumns)
                              .filter((col) => !effectiveExcluded.has(col))
                              .map((column) => column.toString())

                // Cost per conversion only makes sense when the Cost metric exists at this level.
                // At UTM drill-downs (medium/content/term) Cost is excluded because platform
                // cost can't be attributed to a specific UTM value.
                const costAvailable = !effectiveExcluded.has(MarketingAnalyticsBaseColumns.Cost)

                // At ad-group / ad levels, events can't be attributed to a specific ad so
                // conversion goals are dropped entirely.
                const conversionGoalColumns = config.excludesConversionGoals
                    ? []
                    : conversionGoals
                          .map((goal) =>
                              costAvailable
                                  ? [
                                        goal.conversion_goal_name,
                                        `${MarketingAnalyticsConstants.CostPer} ${goal.conversion_goal_name}`,
                                    ]
                                  : [goal.conversion_goal_name]
                          )
                          .flat()

                // ROAS and CAC both divide against spend, so each needs a goal flagged for it and a
                // Cost column at this drill-down level.
                const returnMetricsAvailable =
                    !!featureFlags[FEATURE_FLAGS.MARKETING_ANALYTICS_RETURN_METRICS] &&
                    costAvailable &&
                    !config.excludesConversionGoals
                // Match the backend's eligibility, or a requested column the backend omits just
                // vanishes from the table. ROAS needs a goal whose value is money, so a counting
                // revenue goal doesn't qualify. CAC takes any customer goal: a summing one
                // contributes its paired count column rather than its value.
                const roasColumn =
                    returnMetricsAvailable &&
                    conversionGoals.some((goal) => goal.counts_as_revenue && goalSumsAProperty(goal))
                        ? [MarketingAnalyticsConstants.Roas]
                        : []
                const cacColumn =
                    returnMetricsAvailable && conversionGoals.some((goal) => goal.counts_as_customer)
                        ? [`${MarketingAnalyticsConstants.CostPer} ${MarketingAnalyticsConstants.Customer}`]
                        : []

                const selectColumns = [...baseColumns, ...conversionGoalColumns, ...roasColumn, ...cacColumn].filter(
                    isNotNil
                )
                return selectColumns
            },
        ],
        sortedColumns: [
            (s) => [s.defaultColumns, s.query],
            (defaultColumns: string[], query: DataTableNode) => {
                // pinned columns are always at the beginning of the table in the same order as they are in the default columns
                const pinnedColumns = query?.pinnedColumns || []
                const sortedColumns = [
                    ...defaultColumns.filter((column) => pinnedColumns.includes(column)),
                    ...defaultColumns.filter((column) => !pinnedColumns.includes(column)),
                ]
                return sortedColumns
            },
        ],
    }),
    /* Both in actionToUrl and urlToAction we need to filter out the draft conversion goal columns
    to handle the query params because it's a draft column */
    actionToUrl(({ values }) => ({
        setQuery: () => {
            const marketingQuery = values.query?.source as MarketingAnalyticsTableQuery | undefined
            const searchParams = new URLSearchParams(window.location.search)
            const selectArray =
                marketingQuery?.select?.filter(
                    (column: string) => !isDraftConversionGoalColumn(column, values.draftConversionGoal)
                ) || []

            if (marketingQuery?.orderBy && marketingQuery?.orderBy.length > 0) {
                const [column, direction] = marketingQuery.orderBy[0]
                if (selectArray.includes(column)) {
                    searchParams.set('order_column', column)
                    searchParams.set('order_direction', direction)
                }
            } else {
                searchParams.delete('order_column')
                searchParams.delete('order_direction')
            }

            if (selectArray.length > 0) {
                searchParams.set('select', selectArray.join(','))
            } else {
                searchParams.delete('select')
            }

            if (values.query?.pinnedColumns && values.query?.pinnedColumns.length > 0) {
                searchParams.set('pinned_columns', values.query.pinnedColumns.join(','))
            } else {
                searchParams.delete('pinned_columns')
            }

            return [window.location.pathname, searchParams.toString()]
        },
    })),
    urlToAction(({ actions, values }) => ({
        '*': (_, searchParams) => {
            const hasSelect = searchParams.select !== undefined
            const hasOrder = searchParams.order_column !== undefined || searchParams.order_direction !== undefined
            const hasPinnedColumns = searchParams.pinned_columns !== undefined
            if (!hasSelect && !hasOrder && !hasPinnedColumns) {
                return
            }
            const marketingQuery = values.query?.source as MarketingAnalyticsTableQuery | undefined
            const newSelect = hasSelect
                ? Array.from(new Set<string>((searchParams.select || '').split(','))).filter(
                      (column) => column && !isDraftConversionGoalColumn(column, values.draftConversionGoal)
                  )
                : marketingQuery?.select
            const orderColumn = searchParams.order_column
            const orderDirection = searchParams.order_direction
            const newOrderBy =
                orderColumn &&
                (orderDirection === 'ASC' || orderDirection === 'DESC') &&
                (newSelect ?? values.defaultColumns).includes(orderColumn)
                    ? createMarketingAnalyticsOrderBy(orderColumn, orderDirection)
                    : hasSelect || hasOrder
                      ? undefined
                      : marketingQuery?.orderBy

            actions.setQuery({
                ...values.query,
                kind: NodeKind.DataTableNode,
                source: {
                    ...marketingQuery,
                    kind: NodeKind.MarketingAnalyticsTableQuery,
                    properties: marketingQuery?.properties ?? [],
                    select: newSelect,
                    orderBy: newOrderBy,
                },
                pinnedColumns: hasPinnedColumns
                    ? searchParams.pinned_columns.split(',').filter(Boolean)
                    : hasSelect && values.query?.pinnedColumns
                      ? []
                      : values.query?.pinnedColumns,
            })
        },
    })),
    listeners(({ actions, values }) => ({
        setDraftConversionGoal: ({ goal }: { goal: ConversionGoalFilter | null }) => {
            if (!goal) {
                const marketingQuery = values.query?.source as MarketingAnalyticsTableQuery | undefined
                // If the dynamic conversion goal is removed, we clear the order by
                if (marketingQuery?.orderBy && !values.defaultColumns.includes(marketingQuery?.orderBy[0][0])) {
                    actions.setQuery({
                        ...values.query,
                        source: {
                            ...values.query?.source,
                            orderBy: undefined,
                        },
                    } as DataTableNode)
                }
            }
        },
        setQuery: ({ query }: { query: DataTableNode }) => {
            const marketingQuery = query.source as MarketingAnalyticsTableQuery | undefined
            // Draft goals belong to this visit; only save columns that can be restored later.
            const isSavedColumn = (column: string): boolean =>
                !isDraftConversionGoalColumn(column, values.draftConversionGoal)
            actions.setColumnConfiguration({
                select: marketingQuery?.select?.filter(isSavedColumn),
                orderBy: marketingQuery?.orderBy?.filter(([column]) => isSavedColumn(column)),
                pinnedColumns: query.pinnedColumns?.filter(isSavedColumn) ?? [],
            })
            // If we remove one column from the draft conversion goal, we clear the draft conversion goal completely
            const selectArray =
                marketingQuery?.select?.filter((column: string) =>
                    isDraftConversionGoalColumn(column, values.draftConversionGoal)
                ) || []

            if (selectArray.length === 1) {
                actions.setDraftConversionGoal(null)
            }
        },
    })),
])
