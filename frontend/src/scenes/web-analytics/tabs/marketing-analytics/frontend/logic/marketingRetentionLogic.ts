export const marketingRetentionLogic = kea<marketingRetentionLogicType>([
    path(['scenes', 'webAnalytics', 'marketingRetentionLogic']),
    actions({
        setDates: (dateFrom: string | null, dateTo: string | null) => ({ dateFrom, dateTo }),
        setComparePreviousPeriod: (comparePreviousPeriod: boolean) => ({ comparePreviousPeriod }),
        setBreakdownBy: (breakdownBy: MarketingAnalyticsAttributionBreakdown) => ({ breakdownBy }),
        setExcludeDirectTraffic: (excludeDirectTraffic: boolean) => ({ excludeDirectTraffic }),
        setExcludeUnattributed: (excludeUnattributed: boolean) => ({ excludeUnattributed }),
        setOnlyNewUsers: (onlyNewUsers: boolean) => ({ onlyNewUsers }),
        setOptionsOpen: (optionsOpen: boolean) => ({ optionsOpen }),
    }),
    reducers({
        dateFilter: [
            { dateFrom: '-30d', dateTo: null, interval: getDefaultInterval('-30d', null) } as DateFilter,
            {
                setDates: (_, { dateFrom, dateTo }) => ({
                    dateFrom,
                    dateTo,
                    interval: getDefaultInterval(dateFrom, dateTo),
                }),
            },
        ],
        comparePreviousPeriod: [
            true,
            { setComparePreviousPeriod: (_, { comparePreviousPeriod }) => comparePreviousPeriod },
        ],
        breakdownBy: [
            MarketingAnalyticsAttributionBreakdown.Source as MarketingAnalyticsAttributionBreakdown,
            { setBreakdownBy: (_, { breakdownBy }) => breakdownBy },
        ],
        excludeDirectTraffic: [
            false,
            { setExcludeDirectTraffic: (_, { excludeDirectTraffic }) => excludeDirectTraffic },
        ],
        excludeUnattributed: [false, { setExcludeUnattributed: (_, { excludeUnattributed }) => excludeUnattributed }],
        // Defaults on: without it a channel's cohorts are inflated by the users it acquired long ago.
        onlyNewUsers: [true, { setOnlyNewUsers: (_, { onlyNewUsers }) => onlyNewUsers }],
        optionsOpen: [false, { setOptionsOpen: (_, { optionsOpen }) => optionsOpen }],
    }),
    selectors({
        query: [
            (s) => [
                s.breakdownBy,
                s.excludeDirectTraffic,
                s.excludeUnattributed,
                s.onlyNewUsers,
                s.dateFilter,
                s.comparePreviousPeriod,
            ],
            (
                breakdownBy: MarketingAnalyticsAttributionBreakdown,
                excludeDirectTraffic: boolean,
                excludeUnattributed: boolean,
                onlyNewUsers: boolean,
                dateFilter: DateFilter,
                comparePreviousPeriod: boolean
            ): MarketingAnalyticsRetentionQuery => ({
                kind: NodeKind.MarketingAnalyticsRetentionQuery,
                summary: true,
                comparePreviousPeriod,
                dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo },
                breakdownBy,
                excludeDirectTraffic,
                excludeUnattributed,
                onlyNewUsers,
                properties: [],
            }),
        ],
    }),
])
