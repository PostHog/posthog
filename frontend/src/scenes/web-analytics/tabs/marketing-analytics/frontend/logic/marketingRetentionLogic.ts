export type marketingRetentionLogicType = MakeLogicType<
    marketingRetentionLogicValues,
    marketingRetentionLogicActions,
    Record<string, any>,
    marketingRetentionLogicMeta
>

export const marketingRetentionLogic = kea<marketingRetentionLogicType>([
    path(['scenes', 'webAnalytics', 'marketingRetentionLogic']),
    connect(() => ({
        values: [
            // The tab renders under the scene's shared filter bar, so it reuses that date range rather
            // than owning a second date control the user would have to keep in sync.
            marketingAnalyticsLogic,
            ['dateFilter'],
            marketingAnalyticsSettingsLogic,
            ['conversion_goals'],
        ],
    })),
    actions({
        setBreakdownBy: (breakdownBy: MarketingAnalyticsAttributionBreakdown) => ({ breakdownBy }),
        setRetentionInterval: (retentionInterval: MarketingAnalyticsRetentionInterval) => ({ retentionInterval }),
        setTotalIntervals: (totalIntervals: number) => ({ totalIntervals }),
        setReturningEvent: (returningEvent: MarketingAnalyticsRetentionReturningEvent) => ({ returningEvent }),
        setConversionGoalId: (conversionGoalId: string) => ({ conversionGoalId }),
        setStartEvent: (startEvent: MarketingAnalyticsRetentionStartEvent) => ({ startEvent }),
        setStartConversionGoalId: (startConversionGoalId: string) => ({ startConversionGoalId }),
        setExcludeDirectTraffic: (excludeDirectTraffic: boolean) => ({ excludeDirectTraffic }),
        setExcludeUnattributed: (excludeUnattributed: boolean) => ({ excludeUnattributed }),
        setOnlyNewUsers: (onlyNewUsers: boolean) => ({ onlyNewUsers }),
        setOptionsOpen: (optionsOpen: boolean) => ({ optionsOpen }),
    }),
    reducers({
        breakdownBy: [
            MarketingAnalyticsAttributionBreakdown.Channel as MarketingAnalyticsAttributionBreakdown,
            { setBreakdownBy: (_, { breakdownBy }) => breakdownBy },
        ],
        retentionInterval: [
            MarketingAnalyticsRetentionInterval.Week as MarketingAnalyticsRetentionInterval,
            { setRetentionInterval: (_, { retentionInterval }) => retentionInterval },
        ],
        totalIntervals: [DEFAULT_TOTAL_INTERVALS, { setTotalIntervals: (_, { totalIntervals }) => totalIntervals }],
        returningEvent: [
            MarketingAnalyticsRetentionReturningEvent.Activity as MarketingAnalyticsRetentionReturningEvent,
            { setReturningEvent: (_, { returningEvent }) => returningEvent },
        ],
        conversionGoalId: [
            null as string | null,
            { setConversionGoalId: (_, { conversionGoalId }) => conversionGoalId },
        ],
        startEvent: [
            MarketingAnalyticsRetentionStartEvent.Arrival as MarketingAnalyticsRetentionStartEvent,
            { setStartEvent: (_, { startEvent }) => startEvent },
        ],
        startConversionGoalId: [
            null as string | null,
            { setStartConversionGoalId: (_, { startConversionGoalId }) => startConversionGoalId },
        ],
        excludeDirectTraffic: [
            false,
            { setExcludeDirectTraffic: (_, { excludeDirectTraffic }) => excludeDirectTraffic },
        ],
        excludeUnattributed: [false, { setExcludeUnattributed: (_, { excludeUnattributed }) => excludeUnattributed }],
        // Defaults on: without it a channel's cohorts are inflated by the users it acquired long ago.
        onlyNewUsers: [true, { setOnlyNewUsers: (_, { onlyNewUsers }) => onlyNewUsers }],
        optionsOpen: [false, { setOptionsOpen: (_, { optionsOpen }) => optionsOpen }],
    }),
    selectors({
        attributableGoals: [
            (s) => [s.conversion_goals],
            // Annotated rather than passing `attributableConversionGoals` straight through: typegen
            // cannot infer a bare imported function's return, and silently drops the selector from the
            // generated values when it can't.
            (conversion_goals: ConversionGoalFilter[]): ConversionGoalFilter[] =>
                attributableConversionGoals(conversion_goals),
        ],
        selectedGoalId: [
            (s) => [s.conversionGoalId, s.attributableGoals],
            (conversionGoalId: string | null, attributableGoals: ConversionGoalFilter[]): string | null => {
                const stillAvailable = attributableGoals.some((goal) => goal.conversion_goal_id === conversionGoalId)
                if (conversionGoalId && stillAvailable) {
                    return conversionGoalId
                }
                return attributableGoals[0]?.conversion_goal_id ?? null
            },
        ],
        selectedStartGoalId: [
            (s) => [s.startConversionGoalId, s.attributableGoals],
            (startConversionGoalId: string | null, attributableGoals: ConversionGoalFilter[]): string | null => {
                const stillAvailable = attributableGoals.some(
                    (goal) => goal.conversion_goal_id === startConversionGoalId
                )
                if (startConversionGoalId && stillAvailable) {
                    return startConversionGoalId
                }
                return attributableGoals[0]?.conversion_goal_id ?? null
            },
        ],
        query: [
            (s) => [
                s.breakdownBy,
                s.retentionInterval,
                s.totalIntervals,
                s.returningEvent,
                s.selectedGoalId,
                s.startEvent,
                s.selectedStartGoalId,
                s.excludeDirectTraffic,
                s.excludeUnattributed,
                s.onlyNewUsers,
                s.dateFilter,
            ],
            (
                breakdownBy: MarketingAnalyticsAttributionBreakdown,
                retentionInterval: MarketingAnalyticsRetentionInterval,
                totalIntervals: number,
                returningEvent: MarketingAnalyticsRetentionReturningEvent,
                selectedGoalId: string | null,
                startEvent: MarketingAnalyticsRetentionStartEvent,
                selectedStartGoalId: string | null,
                excludeDirectTraffic: boolean,
                excludeUnattributed: boolean,
                onlyNewUsers: boolean,
                dateFilter: DateFilter
            ): MarketingAnalyticsRetentionQuery => {
                // Both axes fall back when the goal mode has no goal to resolve, so a team with no
                // usable conversion goal still gets a working tab rather than a failing query.
                const countsConversions =
                    returningEvent === MarketingAnalyticsRetentionReturningEvent.ConversionGoal && !!selectedGoalId
                const startsOnConversion =
                    startEvent === MarketingAnalyticsRetentionStartEvent.ConversionGoal && !!selectedStartGoalId
                return {
                    kind: NodeKind.MarketingAnalyticsRetentionQuery,
                    dateRange: { date_from: dateFilter.dateFrom, date_to: dateFilter.dateTo },
                    breakdownBy,
                    retentionInterval,
                    totalIntervals,
                    startEvent: startsOnConversion
                        ? MarketingAnalyticsRetentionStartEvent.ConversionGoal
                        : MarketingAnalyticsRetentionStartEvent.Arrival,
                    ...(startsOnConversion ? { startConversionGoalId: selectedStartGoalId } : {}),
                    returningEvent: countsConversions
                        ? MarketingAnalyticsRetentionReturningEvent.ConversionGoal
                        : MarketingAnalyticsRetentionReturningEvent.Activity,
                    ...(countsConversions ? { conversionGoalId: selectedGoalId } : {}),
                    excludeDirectTraffic,
                    excludeUnattributed,
                    onlyNewUsers,
                    properties: [],
                }
            },
        ],
    }),
])
