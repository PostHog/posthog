import type { LoginForm } from '../login/loginLogic'

export type AuthAccountPath = 'login' | 'signup'

export function accountPathFor(
    precheck: PrecheckResponseType,
    { isDemo, canCreateOrg }: { isDemo: boolean; canCreateOrg: boolean }
): AuthAccountPath {
    // Demo signup logs an existing demo user straight in, and demo users have no password to type.
    if (isDemo) {
        return 'signup'
    }
    // An enforced domain lets its IdP create the account, so signup must not take over. A
    // self-hosted instance that cannot create organizations refuses every signup, so new people
    // there need an invite link instead.
    if (precheck.sso_enforcement || !canCreateOrg) {
        return 'login'
    }
    // Only a definite "no account" goes to signup. An unknown answer (a failed precheck) shows the
    // login step, so an existing account is never pushed into creating a second one.
    return precheck.account_exists === false ? 'signup' : 'login'
}

