import { MakeLogicType, actions, afterMount, connect, kea, listeners, path } from 'kea'
import posthog from 'posthog-js'

import { loginLogic } from 'scenes/authentication/login/loginLogic'
import { AuthEntry, AuthStep, captureAuthStepViewed } from 'scenes/authentication/shared/authStepViewed'
import { readPendingOAuthConnection } from 'scenes/authentication/shared/pendingOAuthConnectionLogic'
import { signupLogic } from 'scenes/authentication/signup/signupForm/signupLogic'
import { preflightLogic } from 'scenes/PreflightCheck/preflightLogic'

import type { PreflightStatus } from '~/types'

import { AuthAccountPath, authLogic } from './authLogic'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface authTelemetryLogicValues {
    entry: AuthEntry // authLogic
    step: AuthStep // authLogic
    preflight: PreflightStatus | null // preflightLogic
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface authTelemetryLogicActions {
    backToEmail: () => {
        value: true
    } // authLogic
    chooseAccountPath: (
        accountPath: AuthAccountPath,
        accountExists: boolean | null
    ) => {
        accountExists: boolean | null
        accountPath: AuthAccountPath
    } // authLogic
    exitCodeVerification: () => {
        value: true
    } // loginLogic
    setCodeVerificationRequired: (email: string) => {
        email: string
    } // loginLogic
    setPanel: (panel: number) => {
        panel: number
    } // signupLogic
    setPendingInvite: (invite: null | import('scenes/authentication/signup/signupForm/signupLogic').PendingInvite) => {
        invite: null | import('scenes/authentication/signup/signupForm/signupLogic').PendingInvite
    } // signupLogic
    reportStepIfChanged: () => {
        value: true
    }
}

export type authTelemetryLogicType = MakeLogicType<authTelemetryLogicValues, authTelemetryLogicActions>

/**
 * Reports the login and signup funnel of the auth page. `step` is derived from three logics, so this
 * listens to every action that can move it and reports a step only when it differs from the last one
 * reported. `loginTelemetryLogic` still reports the password attempts and their failures.
 */
export const authTelemetryLogic = kea<authTelemetryLogicType>([
    path(['scenes', 'authentication', 'auth', 'authTelemetryLogic']),
    connect(() => ({
        values: [authLogic, ['step', 'entry'], preflightLogic, ['preflight']],
        actions: [
            authLogic,
            ['chooseAccountPath', 'backToEmail'],
            loginLogic,
            ['setCodeVerificationRequired', 'exitCodeVerification'],
            signupLogic,
            ['setPanel', 'setPendingInvite'],
        ],
    })),
    actions({
        reportStepIfChanged: true,
    }),
    listeners(({ actions, values, cache }) => ({
        reportStepIfChanged: () => {
            if (cache.reportedStep !== values.step) {
                cache.reportedStep = values.step
                captureAuthStepViewed(values.step, values.entry)
            }
        },
        chooseAccountPath: ({ accountPath, accountExists }) => {
            const connection = readPendingOAuthConnection()
            // pinned: analytics event name and property names
            posthog.capture('auth email submitted', {
                entry: values.entry,
                routed_to: accountPath,
                account_exists: accountExists,
                region: values.preflight?.region,
                oauth_client_name: connection?.clientName,
                oauth_client_id: connection?.clientId,
            })
            actions.reportStepIfChanged()
        },
        backToEmail: () => actions.reportStepIfChanged(),
        setCodeVerificationRequired: () => actions.reportStepIfChanged(),
        exitCodeVerification: () => actions.reportStepIfChanged(),
        setPanel: () => actions.reportStepIfChanged(),
        setPendingInvite: () => actions.reportStepIfChanged(),
    })),
    afterMount(({ actions }) => {
        actions.reportStepIfChanged()
    }),
])
