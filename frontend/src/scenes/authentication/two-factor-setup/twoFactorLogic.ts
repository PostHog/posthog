export const twoFactorLogic = kea<twoFactorLogicType>([
    path(['scenes', 'authentication', 'two-factor-setup', 'twoFactorLogic']),
    props({} as TwoFactorLogicProps),
    connect(() => ({
        values: [preflightLogic, ['preflight'], featureFlagLogic, ['featureFlags'], userLogic, ['user']],
        actions: [userLogic, ['loadUser', 'addFullStageUserFieldsSuccess'], membersLogic, ['loadAllMembers']],
    })),
    actions({
        setGeneralError: (code: string, detail: string) => ({ code, detail }),
        clearGeneralError: true,
        loadStatus: true,
        generateBackupCodes: true,
        disable2FA: true,
        openTwoFactorSetupModal: (forceOpen?: boolean) => ({ forceOpen }),
        closeTwoFactorSetupModal: true,
        toggleDisable2FAModal: (open: boolean) => ({ open }),
        toggleBackupCodesModal: (open: boolean) => ({ open }),
    }),
    // GlobalModals mounts this logic on every page, so the status loads on first read instead of on mount.
    lazyLoaders(() => ({
        status: [
            null as TwoFactorStatusApi | null,
            {
                loadStatus: async () => {
                    return await usersTwoFactorStatusRetrieve('@me')
                },
            },
        ],
    })),
    reducers({
        statusLoadFailed: [
            false,
            {
                loadStatus: () => false,
                loadStatusSuccess: () => false,
                loadStatusFailure: () => true,
            },
        ],
        isTwoFactorSetupModalOpen: [
            false,
            {
                openTwoFactorSetupModal: () => true,
                closeTwoFactorSetupModal: () => false,
            },
        ],
        forceOpenTwoFactorSetupModal: [
            false,
            {
                openTwoFactorSetupModal: (_, { forceOpen }) => !!forceOpen,
                closeTwoFactorSetupModal: () => false,
            },
        ],
        isDisable2FAModalOpen: [
            false,
            {
                toggleDisable2FAModal: (_, { open }) => open,
            },
        ],
        isBackupCodesModalOpen: [
            false,
            {
                toggleBackupCodesModal: (_, { open }) => open,
                // New codes replace the old ones, so a result that lands after close reopens the modal. The
                // user sees them once, and closing again clears them.
                generateBackupCodesSuccess: () => true,
            },
        ],
        generatingCodes: [
            null as { backup_codes: string[] } | null,
            {
                // The backend only returns codes when it generates them, so they leave memory with the modal.
                toggleBackupCodesModal: (state, { open }) => (open ? state : null),
            },
        ],
        generalError: [
            null as { code: string; detail: string } | null,
            {
                setGeneralError: (_, error) => error,
                clearGeneralError: () => null,
            },
        ],
        startSetup: {
            // After a failed call the client cannot know which secret the server checks, so it shows none.
            loadStartSetupFailure: () => null,
        },
    }),
    selectors({
        is2FAEnabled: [(s) => [s.status], (status: TwoFactorStatusApi | null): boolean => !!status?.is_enabled],
        canSwitchOrg: [
            (s) => [s.user],
            (user: null | import('../../../types').UserType): boolean => (user?.organizations || []).length > 1,
        ],
    }),
    loaders(() => ({
        startSetup: [
            null as { qrCodeUrl: string; secret: string; success: boolean } | null,
            {
                loadStartSetup: async () => {
                    // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. usersTwoFactorStartSetupRetrieve() from '~/generated/core/api' serves this route, but its generated types do not describe this call yet, so fix the endpoint's OpenAPI schema first.
                    const response = await api.get('api/users/@me/two_factor_start_setup/')
                    setupResponseCount += 1
                    return { ...response, qrCodeUrl: `/account/two_factor/qrcode/?v=${setupResponseCount}` }
                },
            },
        ],
        generatingCodes: [
            null as { backup_codes: string[] } | null,
            {
                generateBackupCodes: async () => {
                    // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. usersTwoFactorBackupCodesCreate() from '~/generated/core/api' serves this route, but its generated types do not describe this call yet, so fix the endpoint's OpenAPI schema first.
                    return await api.create<any>('api/users/@me/two_factor_backup_codes/')
                },
            },
        ],
    })),
    forms(({ actions }) => ({
        token: {
            defaults: { token: '' },
            errors: ({ token }) => ({
                token: !token ? 'Please enter a token to continue' : undefined,
            }),
            submit: async ({ token }, breakpoint) => {
                breakpoint()
                try {
                    // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. usersTwoFactorValidateCreate() from '~/generated/core/api' serves this route, but its generated types do not describe this call yet, so fix the endpoint's OpenAPI schema first.
                    return await api.create<any>('api/users/@me/two_factor_validate/', { token })
                } catch (e) {
                    const { code, detail } = e as Record<string, any>
                    actions.setGeneralError(code, detail)
                    throw e
                }
            },
        },
    })),
    listeners(({ props, actions, values }) => ({
        openTwoFactorSetupModal: ({ forceOpen }) => {
            // Concurrent setup calls can each create a secret, so only one call runs at a time.
            if (!values.startSetupLoading) {
                posthog.capture('two_factor_setup_started', { forced: !!forceOpen })
                actions.loadStartSetup()
            }
        },
        addFullStageUserFieldsSuccess: ({ user }) => {
            if (mustSetUpTwoFactor(user)) {
                actions.openTwoFactorSetupModal(true)
            }
        },
        submitTokenSuccess: () => {
            posthog.capture('two_factor_setup_completed')
            lemonToast.success('2FA method added successfully')
            actions.loadStatus()
            props.onSuccess?.()
        },
        disable2FA: async () => {
            try {
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. usersTwoFactorDisableCreate() from '~/generated/core/api' serves this route, but its generated types do not describe this call yet, so fix the endpoint's OpenAPI schema first.
                await api.create<any>('api/users/@me/two_factor_disable/')
                posthog.capture('two_factor_disabled')
                lemonToast.success('2FA disabled successfully. The page will reload.')
                actions.loadStatus()

                // Reload to avoid breaking calls on the page if enforce_2fa=True
                setTimeout(() => {
                    window.location.reload()
                }, 3000)
            } catch (e) {
                const { code, detail } = e as Record<string, any>
                actions.setGeneralError(code, detail)
                throw e
            }
        },
        generateBackupCodesSuccess: ({ generatingCodes }) => {
            posthog.capture('two_factor_backup_codes_generated')
            lemonToast.success('Backup codes generated successfully')
            if (values.status && generatingCodes) {
                actions.loadStatusSuccess({
                    ...values.status,
                    backup_codes_remaining: generatingCodes.backup_codes.length,
                })
            }
        },
        closeTwoFactorSetupModal: () => {
            // Clear the form when closing the modal
            actions.resetToken()
        },
    })),

    afterMount(({ actions, values }) => {
        if (mustSetUpTwoFactor(values.user)) {
            actions.openTwoFactorSetupModal(true)
        }
    }),
])
