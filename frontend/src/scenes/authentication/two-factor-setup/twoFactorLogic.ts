// The 2FA and SSO fields are absent until the app context's full stage arrives, and absent is not false.
function mustSetUpTwoFactor(user: UserType | null): boolean {
    return (
        !!user?.organization?.enforce_2fa &&
        user.is_2fa_enabled === false &&
        user.has_sso_enforcement === false &&
        !user.is_impersonated &&
        !user.has_social_auth
    )
}

