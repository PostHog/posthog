import { decode } from 'he'
import { LogicWrapper, MakeLogicType, actions, afterMount, kea, path, reducers } from 'kea'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { getCookie } from 'lib/api'
import { tryJsonParse } from 'lib/utils/json'
import { urls } from 'scenes/urls'

// pinned: the backend sets this cookie (posthog/helpers/oauth_pending_connection.py) and the website reads it
export const PENDING_OAUTH_CONNECTION_COOKIE = 'ph_pending_oauth_connection'

// pinned: analytics property value on `oauth pending connection viewed`
export type PendingOAuthConnectionScreen = 'login' | 'signup' | 'verify_email'

/** The OAuth application a signed-out visitor was asked to authorize before they reached login or signup. */
export interface PendingOAuthConnection {
    clientName: string
    clientId: string
    logoUri: string | null
    /** Host the person returns to when the connection completes, when the client registered a web redirect. */
    redirectHost: string | null
}

function optionalString(value: unknown): string | null {
    return typeof value === 'string' && value ? value : null
}

export function readPendingOAuthConnection(): PendingOAuthConnection | null {
    const raw = getCookie(PENDING_OAUTH_CONNECTION_COOKIE)
    if (!raw) {
        return null
    }
    const parsed = tryJsonParse(raw, null)
    if (!parsed || typeof parsed !== 'object') {
        return null
    }
    const payload = parsed as Record<string, unknown>
    const clientName = optionalString(payload.client_name)
    const clientId = optionalString(payload.client_id)
    if (!clientName || !clientId) {
        return null
    }
    const logoUri = optionalString(payload.logo_uri)
    return {
        // The name is HTML-escaped at ingestion (posthog/api/oauth/client_name.py). Decode it so
        // React's own output escaping renders "&" instead of "&amp;".
        clientName: decode(clientName),
        clientId,
        // Only a web image can render on an https page, so data: and http: URIs are dropped.
        logoUri: logoUri?.startsWith('https://') ? logoUri : null,
        redirectHost: optionalString(payload.redirect_host),
    }
}

/** `lead` opens the sentence, for example "After you log in". */
export function reviewAccessCopy(connection: PendingOAuthConnection, lead: string): string {
    const back = connection.redirectHost ? `, then go back to ${connection.redirectHost}` : ''
    return `${lead}, you'll review what ${connection.clientName} can access${back}.`
}

/** Taken from the path so that a component mounting this logic outside the three auth screens
 * cannot label the event as one of them. */
function screenForPath(pathname: string): PendingOAuthConnectionScreen | null {
    if (pathname === urls.login()) {
        return 'login'
    }
    if (pathname === urls.signup()) {
        return 'signup'
    }
    if (pathname.startsWith(urls.verifyEmail())) {
        return 'verify_email'
    }
    return null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pendingOAuthConnectionLogicValues {
    pendingConnection: PendingOAuthConnection | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface pendingOAuthConnectionLogicActions {
    setPendingConnection: (pendingConnection: PendingOAuthConnection) => {
        pendingConnection: PendingOAuthConnection
    }
}

export type pendingOAuthConnectionLogicType = MakeLogicType<
    pendingOAuthConnectionLogicValues,
    pendingOAuthConnectionLogicActions
>

/** One instance for the whole auth flow, so a panel change inside a scene does not re-read the
 * cookie or report the view again. */
export const pendingOAuthConnectionLogic: LogicWrapper<pendingOAuthConnectionLogicType> =
    kea<pendingOAuthConnectionLogicType>([
        path(['scenes', 'authentication', 'shared', 'pendingOAuthConnectionLogic']),
        actions({
            setPendingConnection: (pendingConnection: PendingOAuthConnection) => ({ pendingConnection }),
        }),
        reducers({
            pendingConnection: [
                null as PendingOAuthConnection | null,
                {
                    setPendingConnection: (_, { pendingConnection }) => pendingConnection,
                },
            ],
        }),
        afterMount(({ actions }) => {
            const pendingConnection = readPendingOAuthConnection()
            if (!pendingConnection) {
                return
            }
            actions.setPendingConnection(pendingConnection)
            const screen = screenForPath(router.values.location.pathname)
            if (screen) {
                posthog.capture('oauth pending connection viewed', {
                    screen,
                    client_name: pendingConnection.clientName,
                    client_id: pendingConnection.clientId,
                })
            }
        }),
    ])
