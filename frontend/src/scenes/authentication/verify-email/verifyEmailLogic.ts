export type verifyEmailLogicType = MakeLogicType<verifyEmailLogicValues, verifyEmailLogicActions>

export const verifyEmailLogic = kea<verifyEmailLogicType>([
    path(['scenes', 'authentication', 'verify-email', 'verifyEmailLogic']),
    connect(() => ({ values: [userLogic, ['user']] })),
    actions({
        setView: (view: 'pending' | 'invalid' | 'success' | null) => ({ view }),
        setUuid: (uuid: string | null) => ({ uuid }),
        requestVerificationCode: (uuid: string) => ({ uuid }),
        setVerificationCode: (code: string) => ({ code }),
        setVerificationCodeError: (error: string | null) => ({ error }),
        submitVerificationCode: true,
    }),
    loaders(({ actions, values }) => ({
        verificationResult: [
            null as VerificationResultType | null,
            {
                submitVerificationCode: async (_, breakpoint) => {
                    const uuid = values.uuid
                    const code = normalizeVerificationCode(values.verificationCode)
                    if (!uuid) {
                        return values.verificationResult
                    }
                    if (!isValidVerificationCode(code)) {
                        actions.setVerificationCodeError('Enter the 6-digit code from your email.')
                        return values.verificationResult
                    }
                    try {
                        const response = await api.create<PostVerifyResponse>(`api/users/verify_email/`, {
                            uuid,
                            code,
                        })
                        clearPendingVerificationEmail()
                        actions.setView('success')
                        await breakpoint(VERIFY_EMAIL_REDIRECT_DELAY_MS)
                        redirectAfterVerification(response, values)
                        return { success: true, uuid }
                    } catch (e: any) {
                        actions.setVerificationCodeError(verificationCodeErrorMessage(e))
                        return values.verificationResult
                    }
                },
            },
        ],
        newlyRequestedVerificationCode: [
            null as boolean | null,
            {
                requestVerificationCode: async ({ uuid }: { uuid: string }) => {
                    try {
                        await api.create(`api/users/request_email_verification/`, { uuid })
                        lemonToast.success('We sent a new code to your email address. Please check your inbox.')
                        // A resend invalidates the previous code, so drop it and its error (the
                        // setVerificationCode reducer clears the error too). The 6-char field is
                        // otherwise full and blocks typing the freshly sent code.
                        actions.setVerificationCode('')
                        actions.setView('pending')
                        return true
                    } catch (e: any) {
                        if (e.code === 'throttled') {
                            lemonToast.error('You have requested a new code too many times. Please try again later.')
                            return false
                        }
                        lemonToast.error('Requesting a new code failed. Please try again later or contact support.')
                        return false
                    }
                },
            },
        ],
    })),
    reducers({
        view: [
            null as 'pending' | 'invalid' | 'success' | null,
            {
                setView: (_, { view }) => view,
            },
        ],
        uuid: [
            null as string | null,
            {
                setUuid: (_, { uuid }) => uuid,
            },
        ],
        verificationCode: [
            '',
            {
                setVerificationCode: (_, { code }) => code,
            },
        ],
        verificationCodeError: [
            null as string | null,
            {
                setVerificationCode: () => null,
                submitVerificationCode: () => null,
                setVerificationCodeError: (_, { error }) => error,
            },
        ],
    }),
    urlToAction(({ actions }) => {
        const showCodeEntry = ({ uuid }: { uuid?: string }): void => {
            if (uuid) {
                actions.setUuid(uuid)
                actions.setView('pending')
            }
        }
        return {
            '/verify_email/:uuid': showCodeEntry,
            // Emails sent before the switch to codes still carry a link with a token. The token no
            // longer verifies, so land the user on the code entry with a resend button.
            '/verify_email/:uuid/:token': showCodeEntry,
            '/verify_email': () => {
                actions.setView('invalid')
            },
        }
    }),
])
