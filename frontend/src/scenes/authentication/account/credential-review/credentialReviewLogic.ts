export type credentialReviewLogicType = MakeLogicType<
    credentialReviewLogicValues,
    credentialReviewLogicActions,
    Record<string, any>,
    credentialReviewLogicMeta
>

export const credentialReviewLogic = kea<credentialReviewLogicType>([
    path(['scenes', 'authentication', 'account', 'credential-review', 'credentialReviewLogic']),
    // connect (not bare import calls) so the list logics are mounted as dependencies
    // of this scene logic. afterMount runs before the review component renders, so without
    // this the load calls below hit an unmounted logic and throw, which sceneLogic
    // catches and turns into a 404 for the whole credential review screen.
    connect(() => ({
        values: [
            connectedAppsLogic,
            ['connectedApps', 'connectedAppsLoading'],
            passkeySettingsLogic,
            ['passkeysLoading'],
            personalAPIKeysLogic,
            ['keysLoading'],
        ],
        actions: [
            connectedAppsLogic,
            [
                'loadConnectedAppsFailure',
                'loadConnectedAppsSuccess',
                'revokeApp',
                'revokeAppFailure',
                'revokeAppSuccess',
            ],
            passkeySettingsLogic,
            ['loadPasskeys'],
            personalAPIKeysLogic,
            ['loadKeys'],
        ],
    })),
    actions({
        keepPartnerConnected: (appId: string) => ({ appId }),
        disconnectPartner: (appId: string) => ({ appId }),
        markComplete: true,
        setCompleting: (completing: boolean) => ({ completing }),
    }),
    reducers({
        keptPartnerIds: [
            [] as string[],
            {
                keepPartnerConnected: (state, { appId }) => (state.includes(appId) ? state : [...state, appId]),
            },
        ],
        revokingAppId: [
            null as string | null,
            {
                revokeApp: (_, { id }) => id,
                revokeAppSuccess: () => null,
                revokeAppFailure: () => null,
            },
        ],
        isCompleting: [
            false,
            {
                setCompleting: (_, { completing }) => completing,
            },
        ],
        connectedAppsLoadFailed: [
            false,
            {
                loadConnectedAppsFailure: () => true,
                loadConnectedAppsSuccess: () => false,
            },
        ],
    }),
    selectors({
        partnersRequiringChoice: [
            (s) => [s.connectedApps],
            (connectedApps: ConnectedAppApi[]): ConnectedAppApi[] =>
                connectedApps.filter((app) => app.requires_access_confirmation),
        ],
        otherConnectedApps: [
            (s) => [s.connectedApps],
            (connectedApps: ConnectedAppApi[]): ConnectedAppApi[] =>
                connectedApps.filter((app) => !app.requires_access_confirmation),
        ],
        partnersAwaitingChoice: [
            (s) => [s.partnersRequiringChoice, s.keptPartnerIds],
            (partnersRequiringChoice: ConnectedAppApi[], keptPartnerIds: string[]): ConnectedAppApi[] =>
                partnersRequiringChoice.filter((app) => !keptPartnerIds.includes(app.id)),
        ],
        continueDisabledReason: [
            (s) => [
                s.revokingAppId,
                s.keysLoading,
                s.passkeysLoading,
                s.connectedAppsLoading,
                s.connectedAppsLoadFailed,
                s.partnersAwaitingChoice,
            ],
            (
                revokingAppId: string | null,
                keysLoading: boolean,
                passkeysLoading: boolean,
                connectedAppsLoading: boolean,
                connectedAppsLoadFailed: boolean,
                partnersAwaitingChoice: ConnectedAppApi[]
            ): string | null => {
                if (revokingAppId) {
                    return 'Disconnecting app…'
                }
                if (keysLoading || passkeysLoading || connectedAppsLoading) {
                    return 'Loading your credentials…'
                }
                if (connectedAppsLoadFailed) {
                    return 'Could not load your connected apps. Reload the page to try again.'
                }
                if (partnersAwaitingChoice.length > 0) {
                    return 'Choose to keep or disconnect each app above'
                }
                return null
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        keepPartnerConnected: ({ appId }) => {
            posthog.capture(PARTNER_ACCESS_CHOSEN_EVENT, { choice: 'keep', application_id: appId })
        },
        disconnectPartner: ({ appId }) => {
            if (values.revokingAppId || values.isCompleting) {
                return
            }
            posthog.capture(PARTNER_ACCESS_CHOSEN_EVENT, { choice: 'disconnect', application_id: appId })
            actions.revokeApp(appId)
        },
        markComplete: async () => {
            if (values.isCompleting || values.continueDisabledReason) {
                return
            }
            actions.setCompleting(true)
            try {
                await usersCredentialsReviewCompleteCreate('@me')
            } catch {
                lemonToast.error('Could not save your review. Try again.')
                actions.setCompleting(false)
                return
            }
            // Flip the local user state's requires_credential_review via reducer before
            // navigating: a stale in-flight loadUser response would otherwise re-trigger
            // the post-login redirect from userLogic.loadUserSuccess.
            userLogic.actions.credentialReviewDismissed()
            userLogic.actions.loadUser()
            const nextPath = getRelativeNextPath(router.values.searchParams['next'], location)
            router.actions.push(nextPath ?? urls.projectHomepage())
        },
    })),
    afterMount(({ actions }) => {
        // Neither logic auto-loads its list on mount, so trigger both here. Otherwise
        // the review screen would render empty until the user hit the settings page.
        actions.loadKeys()
        actions.loadPasskeys()
    }),
])
