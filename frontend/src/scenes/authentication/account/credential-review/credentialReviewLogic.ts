import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import { router } from 'kea-router'

import api, { ApiError } from 'lib/api'
import { timeSensitiveAuthenticationLogic } from 'lib/components/TimeSensitiveAuthentication/timeSensitiveAuthenticationLogic'
import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { passkeySettingsLogic } from 'scenes/settings/user/passkeySettingsLogic'
import { personalAPIKeysLogic } from 'scenes/settings/user/personalAPIKeysLogic'
import { urls } from 'scenes/urls'
import { userLogic } from 'scenes/userLogic'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface credentialReviewLogicValues {
    awaitingReauth: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface credentialReviewLogicActions {
    loadPasskeys: () => any // passkeySettingsLogic
    loadKeys: () => {
        value: true
    } // personalAPIKeysLogic
    submitReauthenticationSuccess: (reauthentication: any) => any // timeSensitiveAuthenticationLogic
    beginPasskey2FASuccess: (passkey2FA: null, payload?: any) => any // timeSensitiveAuthenticationLogic
    markComplete: () => {
        value: true
    }
    setAwaitingReauth: (value: boolean) => {
        value: boolean
    }
}

export type credentialReviewLogicType = MakeLogicType<credentialReviewLogicValues, credentialReviewLogicActions>

export const credentialReviewLogic = kea<credentialReviewLogicType>([
    path(['scenes', 'authentication', 'account', 'credential-review', 'credentialReviewLogic']),
    // connect (not bare import calls) so both list logics are mounted as dependencies
    // of this scene logic. afterMount runs before the review component renders, so without
    // this the load calls below hit an unmounted logic and throw, which sceneLogic
    // catches and turns into a 404 for the whole credential review screen.
    connect(() => ({
        actions: [
            personalAPIKeysLogic,
            ['loadKeys'],
            passkeySettingsLogic,
            ['loadPasskeys'],
            timeSensitiveAuthenticationLogic,
            ['submitReauthenticationSuccess', 'beginPasskey2FASuccess'],
        ],
    })),
    actions({
        markComplete: true,
        setAwaitingReauth: (value: boolean) => ({ value }),
    }),
    reducers({
        awaitingReauth: [
            false,
            {
                setAwaitingReauth: (_, { value }) => value,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        markComplete: async () => {
            try {
                await api.create('api/users/@me/credentials_review_complete/')
            } catch (error) {
                // A session past the freshness window returns a 403 with this code, which
                // apiStatusLogic already answers by opening the re-authentication modal. Skip
                // the error toast so it doesn't contradict that modal, and retry the completion
                // once the user re-authenticates (see the reauth-success listeners below).
                if (error instanceof ApiError && error.code === 'sensitive_action_required_reauth') {
                    actions.setAwaitingReauth(true)
                    return
                }
                lemonToast.error('Could not save your review. Try again.')
                return
            }
            actions.setAwaitingReauth(false)
            // Flip the local user state's requires_credential_review via reducer before
            // navigating: a stale in-flight loadUser response would otherwise re-trigger
            // the post-login redirect from userLogic.loadUserSuccess.
            userLogic.actions.credentialReviewDismissed()
            userLogic.actions.loadUser()
            router.actions.push(urls.projectHomepage())
        },
        submitReauthenticationSuccess: () => {
            if (values.awaitingReauth) {
                actions.markComplete()
            }
        },
        beginPasskey2FASuccess: () => {
            if (values.awaitingReauth) {
                actions.markComplete()
            }
        },
    })),
    afterMount(({ actions }) => {
        // Neither logic auto-loads its list on mount, so trigger both here. Otherwise
        // the review screen would render empty until the user hit the settings page.
        actions.loadKeys()
        actions.loadPasskeys()
    }),
])
