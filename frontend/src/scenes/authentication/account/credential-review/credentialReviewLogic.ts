import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { router } from 'kea-router'
import posthog from 'posthog-js'

import { lemonToast } from 'lib/lemon-ui/LemonToast/LemonToast'
import { getRelativeNextPath } from 'lib/utils/url'
import { connectedAppsLogic } from 'scenes/settings/user/connectedAppsLogic'
import { passkeySettingsLogic } from 'scenes/settings/user/passkeySettingsLogic'
import { personalAPIKeysLogic } from 'scenes/settings/user/personalAPIKeysLogic'
import { urls } from 'scenes/urls'
import { userLogic } from 'scenes/userLogic'

import { usersCredentialsReviewCompleteCreate } from '~/generated/core/api'
import type { ConnectedAppApi } from '~/generated/core/api.schemas'

// pinned: analytics event name and properties, renaming breaks dashboards
const PARTNER_ACCESS_CHOSEN_EVENT = 'credential review partner access chosen'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface credentialReviewLogicValues {
    connectedApps: ConnectedAppApi[] // connectedAppsLogic
    connectedAppsLoading: boolean // connectedAppsLogic
    passkeysLoading: boolean // passkeySettingsLogic
    keysLoading: boolean // personalAPIKeysLogic
    connectedAppsLoadFailed: boolean
    continueDisabledReason: string | null
    isCompleting: boolean
    keptPartnerIds: string[]
    otherConnectedApps: ConnectedAppApi[]
    partnersAwaitingChoice: ConnectedAppApi[]
    partnersRequiringChoice: ConnectedAppApi[]
    revokingAppId: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
