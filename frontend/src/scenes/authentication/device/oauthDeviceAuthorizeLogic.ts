export const oauthDeviceAuthorizeLogic = kea<oauthDeviceAuthorizeLogicType>([
    path(['scenes', 'authentication', 'device', 'oauthDeviceAuthorizeLogic']),
    connect(() => ({
        values: [userLogic, ['user']],
    })),
    actions({
        setUserCode: (userCode: string) => ({ userCode }),
        submitCode: true,
        goToLogin: true,
        setOrganizationId: (organizationId: string | null) => ({ organizationId }),
        setProjectId: (projectId: number | null) => ({ projectId }),
        setShowCreateProject: (show: boolean) => ({ show }),
        createProject: (name: string) => ({ name }),
        // Null when the project wasn't created, or was created in an organization the person has left.
        createProjectDone: (project: DeviceProject | null) => ({ project }),
        setScopeAccess: (scopeObject: string, level: ScopeAccessLevel) => ({ scopeObject, level }),
        setScopeGroupAccess: (scopeObjects: string[], level: ScopeAccessLevel) => ({ scopeObjects, level }),
    }),
    reducers({
        // The person's picks, per scope object. Absent entries keep the requested level, and every
        // pick is clamped between the required floor and the requested ceiling in scopeRows.
        scopeAccessSelections: [
            { bulk: null, overrides: {} } as ScopeAccessSelections,
            {
                setScopeAccess: (state, { scopeObject, level }) => ({
                    ...state,
                    overrides: { ...state.overrides, [scopeObject]: level },
                }),
                setScopeGroupAccess: (state, { scopeObjects, level }) => ({
                    ...state,
                    overrides: {
                        ...state.overrides,
                        ...Object.fromEntries(scopeObjects.map((scopeObject) => [scopeObject, level])),
                    },
                }),
                lookUpCodeSuccess: () => ({ bulk: null, overrides: {} }),
            },
        ],
        userCode: ['', { setUserCode: (_, { userCode }) => userCode.toUpperCase() }],
        // Stays on until the page unloads, so the button can't send the person to login twice.
        goingToLogin: [false, { goToLogin: () => true }],
        organizationId: [null as string | null, { setOrganizationId: (_, { organizationId }) => organizationId }],
        projectId: [
            null as number | null,
            {
                setProjectId: (_, { projectId }) => projectId,
                setOrganizationId: () => null,
                createProjectDone: (state, { project }) => project?.id ?? state,
            },
        ],
        showCreateProject: [
            false,
            {
                setShowCreateProject: (_, { show }) => show,
                setOrganizationId: () => false,
                createProjectDone: (state, { project }) => (project ? false : state),
            },
        ],
        creatingProject: [false, { createProject: () => true, createProjectDone: () => false }],
        // Kept apart from the loaded list, so a list request that started before the project existed can't drop it.
        createdProjects: [
            [] as DeviceProject[],
            {
                createProjectDone: (state, { project }) => (project ? [...state, project] : state),
                setOrganizationId: () => [],
            },
        ],
        projectsError: [
            null as string | null,
            {
                loadProjects: () => null,
                loadProjectsFailure: (_, { errorObject }) => deviceErrorMessage(errorObject),
            },
        ],
        error: [
            null as string | null,
            {
                lookUpCodeFailure: (_, { errorObject }) => deviceErrorMessage(errorObject),
                approveFailure: (_, { errorObject }) => deviceErrorMessage(errorObject),
                denyFailure: (_, { errorObject }) => deviceErrorMessage(errorObject),
                lookUpCode: () => null,
                approve: () => null,
                deny: () => null,
                setUserCode: () => null,
            },
        ],
    }),
    loaders(({ values }) => ({
        deviceGrant: [
            null as DeviceGrantDetailsApi | null,
            {
                lookUpCode: async () => await oauthDeviceLookupCreate({ user_code: values.userCode }),
            },
        ],
        projects: [
            [] as DeviceProject[],
            {
                loadProjects: async (organizationId: string, breakpoint) => {
                    const projects: DeviceProject[] = []
                    for (let offset = 0; ; offset += PROJECTS_PAGE_SIZE) {
                        const page = await organizationsProjectsList(organizationId, {
                            limit: PROJECTS_PAGE_SIZE,
                            offset,
                        })
                        // Drops the answer for an organization the person already switched away from.
                        breakpoint()
                        projects.push(...page.results.map(({ id, name }) => ({ id, name })))
                        if (!page.next) {
                            return projects
                        }
                    }
                },
            },
        ],
        decision: [
            null as DeviceDecisionEnumApi | null,
            {
                approve: async () => {
                    const { deviceGrant, projectId } = values
                    if (!deviceGrant || projectId === null) {
                        return null
                    }
                    return (
                        await oauthDeviceApproveCreate({
                            user_code: deviceGrant.user_code,
                            project_id: projectId,
                            scopes: values.keptScopes,
                        })
                    ).status
                },
                deny: async () => {
                    if (!values.deviceGrant) {
                        return null
                    }
                    return (await oauthDeviceDenyCreate({ user_code: values.deviceGrant.user_code })).status
                },
            },
        ],
    })),
    reducers({
        // Another organization, or a failed load, must not leave the previous organization's projects
        // selectable while the organization picker shows a different one.
        projects: {
            setOrganizationId: () => [],
            loadProjectsFailure: () => [],
        },
        // A code that expired during review goes back to code entry, so the person can type the new one.
        deviceGrant: {
            approveFailure: (state, { errorObject }) => (isInvalidCode(errorObject) ? null : state),
            denyFailure: (state, { errorObject }) => (isInvalidCode(errorObject) ? null : state),
        },
    }),
    selectors({
        organizations: [(s) => [s.user], (user: UserType | null) => user?.organizations ?? []],
        projectChoices: [
            (s) => [s.projects, s.createdProjects],
            (projects: DeviceProject[], createdProjects: DeviceProject[]): DeviceProject[] => [
                ...projects,
                ...createdProjects.filter((created) => !projects.some((project) => project.id === created.id)),
            ],
        ],
        isStepUp: [
            (s) => [s.deviceGrant, s.projectId, s.organizationId],
            // A login that adds nothing, such as logging in again for the same project, lists every scope.
            (
                deviceGrant: DeviceGrantDetailsApi | null,
                projectId: number | null,
                organizationId: string | null
            ): boolean => {
                const added = deviceGrant ? addedScopes(deviceGrant, projectId, organizationId).length : 0
                return added > 0 && added < (deviceGrant?.scopes.length ?? 0)
            },
        ],
        identityScopeDescriptions: [
            (s) => [s.deviceGrant],
            (deviceGrant: DeviceGrantDetailsApi | null): string[] =>
                identityScopeDescriptions(deviceGrant?.scopes ?? []),
        ],
        consentResourceScopes: [
            (s) => [s.deviceGrant],
            (deviceGrant: DeviceGrantDetailsApi | null): string[] =>
                getMinimumEquivalentScopes(deviceGrant?.scopes ?? []).filter((scope) => scope.includes(':')),
        ],
        requiredScopeLevels: [
            (s) => [s.deviceGrant],
            (deviceGrant: DeviceGrantDetailsApi | null): Map<string, RequiredLevel> =>
                requiredLevelsFromScopes(deviceGrant?.required_scopes ?? []),
        ],
        // One row per scope object, built the same way as on the OAuth consent screen. Only required
        // scopes set a floor: a device login replaces the client's stored token, so an earlier grant
        // gives the person no reason to keep that access.
        scopeRows: [
            (s) => [s.deviceGrant, s.consentResourceScopes, s.requiredScopeLevels, s.scopeAccessSelections],
            (
                deviceGrant: DeviceGrantDetailsApi | null,
                consentResourceScopes: string[],
                requiredScopeLevels: Map<string, RequiredLevel>,
                scopeAccessSelections: ScopeAccessSelections
            ): OAuthScopeRow[] =>
                deviceGrant
                    ? buildOAuthScopeRows(
                          consentResourceScopes,
                          scopeAccessSelections,
                          requiredScopeLevels,
                          new Map(),
                          deviceGrant.client_name
                      )
                    : [],
        ],
        requiredScopeRows: [
            (s) => [s.scopeRows],
            (scopeRows: OAuthScopeRow[]): OAuthScopeRow[] => scopeRows.filter((row) => row.locked),
        ],
        adjustableScopeRows: [
            (s) => [s.scopeRows],
            (scopeRows: OAuthScopeRow[]): OAuthScopeRow[] => scopeRows.filter((row) => !row.locked),
        ],
        scopeGroups: [
            (s) => [s.adjustableScopeRows],
            (adjustableScopeRows: OAuthScopeRow[]): OAuthScopeGroup[] | null => scopeGroupsToShow(adjustableScopeRows),
        ],
        allScopesRequired: [
            (s) => [s.scopeRows],
            (scopeRows: OAuthScopeRow[]): boolean => scopeRows.length > 0 && scopeRows.every((row) => row.locked),
        ],
        // Why the locked rows can't be removed, such as the scopes a step-up adds.
        requiredScopesNote: [
            (s) => [s.requiredScopeRows, s.allScopesRequired, s.deviceGrant],
            (
                requiredScopeRows: OAuthScopeRow[],
                allScopesRequired: boolean,
                deviceGrant: DeviceGrantDetailsApi | null
            ): string | null => {
                if (requiredScopeRows.length === 0) {
                    return null
                }
                const which = allScopesRequired ? 'all of these permissions' : 'the permissions marked Required'
                return `${deviceGrant?.client_name} needs ${which}, so you can't remove them. To refuse them, deny the login.`
            },
        ],
        scopeSummary: [
            (s) => [s.scopeRows, s.deviceGrant],
            (scopeRows: OAuthScopeRow[], deviceGrant: DeviceGrantDetailsApi | null): string =>
                scopeSummary(scopeRows, deviceGrant?.client_name ?? ''),
        ],
        // What approval sends: the required scopes as requested, identity scopes included, and the
        // resource scopes at the level the person picked.
        keptScopes: [
            (s) => [s.deviceGrant, s.scopeRows],
            (deviceGrant: DeviceGrantDetailsApi | null, scopeRows: OAuthScopeRow[]): string[] => {
                if (!deviceGrant) {
                    return []
                }
                const resources = grantedResourceScopes(scopeRows, deviceGrant.scopes, () => [])
                return Array.from(new Set([...deviceGrant.required_scopes, ...resources]))
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        submitCode: () => {
            if (values.user) {
                actions.lookUpCode()
            } else {
                actions.goToLogin()
            }
        },
        goToLogin: () => {
            // A page load, not a client-side route change: the server sends the person to login with the
            // code's app named, so the login, signup and verification screens show what they are connecting.
            window.location.assign(combineUrl(urls.oauthDeviceAuthorize(), { code: values.userCode.trim() }).url)
        },
        setOrganizationId: ({ organizationId }) => {
            if (organizationId) {
                actions.loadProjects(organizationId)
            }
        },
        createProject: async ({ name }) => {
            const { organizationId } = values
            if (!organizationId) {
                actions.createProjectDone(null)
                return
            }
            try {
                const project = await organizationsProjectsCreate(organizationId, { name })
                posthog.capture('oauth_project_created', { flow: 'device' })
                actions.createProjectDone(
                    values.organizationId === organizationId ? { id: project.id, name: project.name ?? name } : null
                )
            } catch (error) {
                lemonToast.error(`Couldn't create the project. ${deviceErrorMessage(error)}`)
                actions.createProjectDone(null)
            }
        },
        loadProjectsSuccess: ({ projects }) => {
            const currentProjectId = values.user?.team?.project_id
            if (values.projectId === null && projects.some((project) => project.id === currentProjectId)) {
                actions.setProjectId(currentProjectId ?? null)
            }
        },
    })),
    urlToAction(({ actions, values }) => ({
        '/device': (_, searchParams) => {
            const code = typeof searchParams.code === 'string' ? searchParams.code : ''
            if (code && code.toUpperCase() !== values.userCode) {
                actions.setUserCode(code)
                if (values.user) {
                    actions.lookUpCode()
                }
            }
        },
    })),
    afterMount(({ actions, values }) => {
        const organizationId = values.user?.organization?.id ?? values.user?.organizations?.[0]?.id
        if (organizationId) {
            actions.setOrganizationId(organizationId)
        }
    }),
])
