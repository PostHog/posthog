interface DeviceProject {
    id: number
    name: string
}

function deviceErrorMessage(error: unknown): string {
    if (error instanceof ApiError) {
        if (error.status === 429) {
            return 'Too many attempts. Wait a minute, then try again.'
        }
        if (typeof error.data?.error_description === 'string') {
            return error.data.error_description
        }
        if (error.detail) {
            return error.detail
        }
    }
    return "Couldn't reach PostHog. Check your connection and try again."
}

// The server's answer for a code that is wrong, expired or already used. Retrying it can't work.
function isInvalidCode(error: unknown): boolean {
    return error instanceof ApiError && error.data?.error === 'invalid_code'
}

// The project picker loads every page, so a project past the first page can still be picked.
const PROJECTS_PAGE_SIZE = 100

// The scopes the person already gave this client that work in the chosen project. A grant limited to
// another project or organization gives nothing here.
function grantedInProject(
    grant: DeviceGrantDetailsApi,
    projectId: number | null,
    organizationId: string | null
): string[] {
    return grant.granted_scopes
        .filter(
            (entry) =>
                (entry.project_id === null || entry.project_id === projectId) &&
                (entry.organization_id === null || entry.organization_id === organizationId)
        )
        .flatMap((entry) => entry.scopes)
}

// The scopes a step-up asks for beyond what the person already granted in the chosen project.
function addedScopes(grant: DeviceGrantDetailsApi, projectId: number | null, organizationId: string | null): string[] {
    const granted = new Set(grantedInProject(grant, projectId, organizationId))
    return grant.scopes.filter((scope) => !granted.has(scope))
}

const areas = (count: number): string => `${count} ${count === 1 ? 'area' : 'areas'}`

// One sentence for the collapsed permissions panel, counted from the levels the person picked.
function scopeSummary(rows: OAuthScopeRow[], appName: string): string {
    const { write, read } = countScopeRowsByLevel(rows)
    if (write && read) {
        return `${appName} can view and change data in ${areas(write)}, and view data in ${read} more.`
    }
    if (write) {
        return `${appName} can view and change data in ${areas(write)}.`
    }
    if (read) {
        return `${appName} can view data in ${areas(read)}.`
    }
    return `${appName} can only see your account details.`
}

