export const recentLoginsLogic = kea<recentLoginsLogicType>([
    path(['scenes', 'authentication', 'login', 'recentLoginsLogic']),
    connect(() => ({
        values: [loginLogic, ['isPasswordLoginUnavailable', 'codeVerificationRequired', 'isAccountFormRequestedByUrl']],
        actions: [
            loginLogic,
            ['setLoginValue', 'precheck', 'requestAccountFormFromUrl'],
            passkeyLogic,
            ['beginPasskeyLogin', 'passkeyAuthenticationCancelled', 'startPasskeyAuthenticationFailure'],
        ],
    })),
    actions({
        setRecentLogins: (recentLogins: RecentLogin[]) => ({ recentLogins }),
        selectRecentLogin: (recentLogin: RecentLogin) => ({ recentLogin }),
        selectAnotherAccount: true,
        returnToRecentLogins: true,
        showAccountForm: true,
        setCheckingEmail: (email: string | null) => ({ email }),
    }),
    reducers({
        recentLogins: [
            [] as RecentLogin[],
            {
                setRecentLogins: (_, { recentLogins }) => recentLogins,
            },
        ],
        isAccountFormShown: [
            false,
            {
                selectAnotherAccount: () => true,
                showAccountForm: () => true,
                returnToRecentLogins: () => false,
            },
        ],
        isPasswordFocusRequested: [
            false,
            {
                selectRecentLogin: (_, { recentLogin }) => !recentLogin.method || recentLogin.method === 'password',
                selectAnotherAccount: () => false,
                returnToRecentLogins: () => false,
            },
        ],
        checkingEmail: [
            null as string | null,
            {
                setCheckingEmail: (_, { email }) => email,
            },
        ],
    }),
    selectors({
        hasRecentLogins: [(s) => [s.recentLogins], (recentLogins: RecentLogin[]): boolean => recentLogins.length > 0],
        // The full form owns code entry and accounts without a password, so the list never covers them
        isChooserShown: [
            (s) => [s.hasRecentLogins, s.isAccountFormShown, s.codeVerificationRequired, s.isPasswordLoginUnavailable],
            (
                hasRecentLogins: boolean,
                isAccountFormShown: boolean,
                codeVerificationRequired: boolean,
                isPasswordLoginUnavailable: boolean
            ): boolean =>
                hasRecentLogins && !isAccountFormShown && !codeVerificationRequired && !isPasswordLoginUnavailable,
        ],
        canReturnToRecentLogins: [
            (s) => [s.hasRecentLogins, s.isAccountFormShown, s.codeVerificationRequired, s.isPasswordLoginUnavailable],
            (
                hasRecentLogins: boolean,
                isAccountFormShown: boolean,
                codeVerificationRequired: boolean,
                isPasswordLoginUnavailable: boolean
            ): boolean =>
                hasRecentLogins && isAccountFormShown && !codeVerificationRequired && !isPasswordLoginUnavailable,
        ],
    }),
    listeners(({ actions, values }) => ({
        selectRecentLogin: async ({ recentLogin: { email, method } }) => {
            if (method === 'passkey') {
                // No precheck here, because a precheck for an account with passkeys opens a second prompt
                actions.setLoginValue('email', email)
                actions.beginPasskeyLogin()
                return
            }
            if (!method || method === 'password') {
                // Without `autoAttempt`, so the click only fills the form and never leaves the page on its own
                actions.showAccountForm()
                actions.setLoginValue('email', email)
                actions.precheck({ email })
                return
            }
            if (values.checkingEmail) {
                return
            }
            // Re-check enforcement outside loginLogic, whose precheck can open the passkey prompt
            actions.setCheckingEmail(email)
            let provider: SSOProvider = method
            try {
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                const response = await api.create<{ sso_enforcement?: SSOProvider | null }>('api/login/precheck', {
                    email,
                })
                provider = response.sso_enforcement ?? method
            } catch {
                // A failed check falls back to the stored method, so the row still works
            } finally {
                actions.setCheckingEmail(null)
            }
            window.location.assign(getSocialLoginUrl(provider, { email }))
        },
        passkeyAuthenticationCancelled: () => {
            if (values.isChooserShown) {
                actions.showAccountForm()
            }
        },
        startPasskeyAuthenticationFailure: () => {
            if (values.isChooserShown) {
                actions.showAccountForm()
            }
        },
        requestAccountFormFromUrl: () => {
            actions.showAccountForm()
        },
    })),
    afterMount(({ actions, values }) => {
        actions.setRecentLogins(readRecentLogins())
        if (values.isAccountFormRequestedByUrl) {
            actions.showAccountForm()
        }
    }),
])
