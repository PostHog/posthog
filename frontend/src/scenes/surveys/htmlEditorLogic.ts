import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    propsChanged,
    reducers,
    selectors,
} from 'kea'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'

import { SurveyQuestionDescriptionContentType } from '~/types'

import { htmlToPlainText, isRichTextCompatibleHtml, plainTextToHtml } from './surveyRichText'

export type HTMLEditorTab = SurveyQuestionDescriptionContentType | 'rich'
export type HTMLEditorConversion = 'toHtml' | 'toText'

export interface HTMLEditorLogicProps {
    editorKey: string
    value: string
    activeTab: SurveyQuestionDescriptionContentType
    onChange: (value: string) => void
    onTabChange: (key: SurveyQuestionDescriptionContentType) => void
}

