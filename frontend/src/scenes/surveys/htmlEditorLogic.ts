export type htmlEditorLogicType = MakeLogicType<
    htmlEditorLogicValues,
    htmlEditorLogicActions,
    HTMLEditorLogicProps,
    htmlEditorLogicMeta
>

function syncFromProps(logic: htmlEditorLogicType): void {
    const { props, values, actions, cache } = logic
    if (props.value !== values.value || props.activeTab !== values.activeTab) {
        actions.syncProps(props.value, props.activeTab)
    }
    if (!values.htmlTab && props.activeTab === 'html') {
        actions.setHtmlTab(values.richTextCompatible ? 'rich' : 'html')
    }
    const conversion = values.pendingConversion
    if (!conversion || props.activeTab !== (conversion === 'toHtml' ? 'html' : 'text')) {
        return
    }
    // This runs while React renders, and a parent that keeps the value in React state can't update then
    // A second run of this setup must not convert again, because that escapes HTML that is already converted
    cache.disposables.add(
        () => {
            const timer = window.setTimeout(() => {
                if (logic.values.pendingConversion !== conversion) {
                    return
                }
                actions.setPendingConversion(null)
                if (props.value) {
                    props.onChange(
                        conversion === 'toHtml' ? plainTextToHtml(props.value) : htmlToPlainText(props.value)
                    )
                }
            }, 0)
            return () => window.clearTimeout(timer)
        },
        'pendingConversion',
        { pauseOnPageHidden: false }
    )
}

export const htmlEditorLogic: LogicWrapper<htmlEditorLogicType> = kea<htmlEditorLogicType>([
    props({} as HTMLEditorLogicProps),
    key((props) => props.editorKey),
    path((key) => ['scenes', 'surveys', 'htmlEditorLogic', key]),
    connect(() => ({ values: [featureFlagLogic, ['featureFlags']] })),
    actions({
        syncProps: (value: string, activeTab: SurveyQuestionDescriptionContentType) => ({ value, activeTab }),
        selectTab: (tab: HTMLEditorTab) => ({ tab }),
        setHtmlTab: (htmlTab: 'rich' | 'html') => ({ htmlTab }),
        setPendingConversion: (conversion: HTMLEditorConversion | null) => ({ conversion }),
    }),
    reducers(({ props }) => ({
        // Selectors can't read props here, because kea changes the props object in place and the selector cache misses the change
        value: [props.value, { syncProps: (_, { value }) => value }],
        activeTab: [props.activeTab, { syncProps: (_, { activeTab }) => activeTab }],
        // Rich text and HTML both store 'html'. The tab is picked once, so an edit in the HTML tab does not move the author.
        htmlTab: [
            null as 'rich' | 'html' | null,
            {
                setHtmlTab: (_, { htmlTab }) => htmlTab,
            },
        ],
        pendingConversion: [
            null as HTMLEditorConversion | null,
            {
                setPendingConversion: (_, { conversion }) => conversion,
            },
        ],
    })),
    selectors({
        richTextEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.SURVEYS_RICH_TEXT_DESCRIPTIONS],
        ],
        richTextCompatible: [(s) => [s.value], (value: string): boolean => isRichTextCompatibleHtml(value ?? '')],
        shownTab: [
            (s) => [s.activeTab, s.richTextEnabled, s.htmlTab, s.richTextCompatible],
            (
                activeTab: SurveyQuestionDescriptionContentType,
                richTextEnabled: boolean,
                htmlTab: 'html' | 'rich' | null,
                richTextCompatible: boolean
            ): HTMLEditorTab => {
                if (activeTab === 'text') {
                    return 'text'
                }
                if (!richTextEnabled) {
                    return 'html'
                }
                return htmlTab ?? (richTextCompatible ? 'rich' : 'html')
            },
        ],
        textTabValue: [
            (s) => [s.value, s.pendingConversion],
            (value: string, pendingConversion: HTMLEditorConversion | null): string =>
                pendingConversion === 'toText' ? htmlToPlainText(value ?? '') : (value ?? ''),
        ],
        htmlTabValue: [
            (s) => [s.value, s.pendingConversion],
            (value: string, pendingConversion: HTMLEditorConversion | null): string =>
                pendingConversion === 'toHtml' ? plainTextToHtml(value ?? '') : (value ?? ''),
        ],
    }),
    listeners(({ actions, props }) => ({
        selectTab: ({ tab }) => {
            if (tab !== 'text') {
                actions.setHtmlTab(tab)
            }
            const nextContentType = tab === 'text' ? 'text' : 'html'
            if (nextContentType === props.activeTab) {
                return
            }
            // The parent stores the new content type first. The value converts when the new props arrive, so the two updates do not race.
            actions.setPendingConversion(tab === 'text' ? 'toText' : 'toHtml')
            props.onTabChange(nextContentType)
        },
    })),
    afterMount((logic) => syncFromProps(logic)),
    propsChanged((logic) => syncFromProps(logic)),
])
