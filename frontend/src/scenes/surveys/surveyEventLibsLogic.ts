import { MakeLogicType, actions, kea, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'

import { hogql } from '~/queries/utils'

/**
 * `$lib` values for SDKs that run in the user's browser or app, where survey event triggers are
 * evaluated. Anything else (posthog-python, posthog-node, the capture API, ...) can never fire a
 * trigger, because the client SDK never sees the event.
 */
const CLIENT_SIDE_LIBS = new Set([
    'web',
    'js',
    'posthog-js',
    'posthog-js-lite',
    'posthog-react-native',
    'posthog-ios',
    'posthog-android',
    'posthog-flutter',
    'posthog-kmp',
])

const LOOKBACK_DAYS = 30
const SAMPLE_SIZE = 500

function isClientSideLib(lib: string): boolean {
    return CLIENT_SIDE_LIBS.has(lib)
}

export function hasOnlyNonClientSideLibs(libs: string[] | undefined): boolean {
    return !!libs && libs.length > 0 && libs.every((lib) => !isClientSideLib(lib))
}

async function fetchLibsForEvent(eventName: string): Promise<string[]> {
    // No ORDER BY and a row limit inside the subquery so ClickHouse can stop reading early - this
    // runs while someone edits a survey, and trigger events can be very high volume
    const query = hogql`
        SELECT arrayDistinct(groupArray(lib)) AS libs
        FROM (
            SELECT properties.$lib AS lib
            FROM events
            WHERE event = ${eventName}
              AND timestamp >= now() - INTERVAL ${LOOKBACK_DAYS} DAY
            LIMIT ${SAMPLE_SIZE}
        )`

    try {
        const response = await api.queryHogQL(query, {
            scene: 'Survey',
            productKey: 'surveys',
            name: 'survey_trigger_event_libs',
        })
        const libs = (response.results?.[0]?.[0] ?? []) as string[]
        return libs.filter((lib) => !!lib)
    } catch {
        // An unanswerable query means we don't know where the event comes from, so warn about nothing
        return []
    }
}

