/**
 * Looks up which SDKs each of a survey's trigger events has recently been captured from, so the
 * editor can warn about events that only ever arrive server-side and can never fire a trigger.
 */
export const surveyEventLibsLogic = kea<surveyEventLibsLogicType>([
    props({} as SurveyLogicProps),
    key(({ id }) => id),
    path((key) => ['scenes', 'surveys', 'surveyEventLibsLogic', key]),
    connect((props: SurveyLogicProps) => ({
        values: [surveyLogic(props), ['survey']],
    })),
    actions({
        loadEventLibs: (eventNames: string[]) => ({ eventNames }),
    }),
    loaders(({ values }) => ({
        libsByEvent: [
            {} as Record<string, string[]>,
            {
                loadEventLibs: async ({ eventNames }, breakpoint) => {
                    const missing = eventNames.filter((eventName) => !(eventName in values.libsByEvent))
                    if (missing.length === 0) {
                        return values.libsByEvent
                    }
                    await breakpoint(300)
                    const fetched = await Promise.all(
                        missing.map(async (eventName) => [eventName, await fetchLibsForEvent(eventName)] as const)
                    )
                    breakpoint()
                    return { ...values.libsByEvent, ...Object.fromEntries(fetched) }
                },
            },
        ],
    })),
    selectors({
        triggerEventNames: [
            (s) => [s.survey],
            (survey: Survey | NewSurvey): string[] => [
                ...new Set(
                    [...(survey.conditions?.events?.values ?? []), ...(survey.conditions?.cancelEvents?.values ?? [])]
                        .map((event) => event?.name)
                        .filter((name): name is string => !!name)
                ),
            ],
        ],
        nonClientSideLibsByEvent: [
            (s) => [s.libsByEvent],
            (libsByEvent: Record<string, string[]>): Record<string, string[]> =>
                Object.fromEntries(Object.entries(libsByEvent).filter(([, libs]) => hasOnlyNonClientSideLibs(libs))),
        ],
    }),
    subscriptions(({ actions }) => ({
        triggerEventNames: (eventNames: string[]) => {
            if (eventNames.length > 0) {
                actions.loadEventLibs(eventNames)
            }
        },
    })),
])
