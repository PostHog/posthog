/**
 * Caches which SDKs each event name has recently been captured from, so the survey editor can warn
 * about trigger events that only ever arrive server-side. Not keyed by survey: the answer is a
 * property of the project's event stream.
 */
export const surveyEventLibsLogic = kea<surveyEventLibsLogicType>([
    path(['scenes', 'surveys', 'surveyEventLibsLogic']),
    actions({
        loadEventLibs: (eventNames: string[]) => ({ eventNames }),
    }),
    loaders(({ values }) => ({
        libsByEvent: [
            {} as Record<string, string[]>,
            {
                loadEventLibs: async ({ eventNames }, breakpoint) => {
                    const missing = eventNames.filter((eventName) => !(eventName in values.libsByEvent))
                    if (missing.length === 0) {
                        return values.libsByEvent
                    }
                    await breakpoint(300)
                    const fetched = await Promise.all(
                        missing.map(async (eventName) => [eventName, await fetchLibsForEvent(eventName)] as const)
                    )
                    breakpoint()
                    return { ...values.libsByEvent, ...Object.fromEntries(fetched) }
                },
            },
        ],
    })),
    selectors({
        nonClientSideLibsByEvent: [
            (s) => [s.libsByEvent],
            (libsByEvent: Record<string, string[]>): Record<string, string[]> =>
                Object.fromEntries(Object.entries(libsByEvent).filter(([, libs]) => hasOnlyNonClientSideLibs(libs))),
        ],
    }),
])
