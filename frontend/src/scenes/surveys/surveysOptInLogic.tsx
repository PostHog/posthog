import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import posthog from 'posthog-js'

import { LemonDialog } from 'lib/lemon-ui/LemonDialog'
import { SurveysOptInConfirmation } from 'scenes/surveys/components/SurveysOptInConfirmation'
import { getSurveyDisplayConditionsSummary } from 'scenes/surveys/utils'
import { teamLogic } from 'scenes/teamLogic'

import { Survey, SurveyType } from '~/types'

import { surveysList } from 'products/surveys/frontend/generated/api'

const RUNNING_SURVEYS_PAGE_SIZE = 100

async function loadUntargetedRunningSurveys(projectId: string): Promise<Survey[]> {
    const surveys: Survey[] = []
    let hasMore = true
    while (hasMore) {
        const response = await surveysList(projectId, {
            status: 'running',
            type: SurveyType.Popover,
            archived: false,
            limit: RUNNING_SURVEYS_PAGE_SIZE,
            offset: surveys.length,
        })
        // getSurveyDisplayConditionsSummary reads the handwritten Survey shape of the same payload.
        surveys.push(...(response.results as unknown as Survey[]))
        hasMore = response.results.length > 0 && surveys.length < response.count
    }
    return surveys.filter((survey) => getSurveyDisplayConditionsSummary(survey).length === 0)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface surveysOptInLogicValues {
    currentProjectId: number | string // teamLogic
    checkingRunningSurveys: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface surveysOptInLogicActions {
    updateCurrentTeam: (payload: Partial<import('~/types').TeamType>) => Partial<import('~/types').TeamType> // teamLogic
    setCheckingRunningSurveys: (checking: boolean) => {
        checking: boolean
    }
    setSurveysOptIn: (optIn: boolean) => {
        optIn: boolean
    }
}

export type surveysOptInLogicType = MakeLogicType<surveysOptInLogicValues, surveysOptInLogicActions>

export const surveysOptInLogic = kea<surveysOptInLogicType>([
    path(['scenes', 'surveys', 'surveysOptInLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
        actions: [teamLogic, ['updateCurrentTeam']],
    })),
    actions({
        setSurveysOptIn: (optIn: boolean) => ({ optIn }),
        setCheckingRunningSurveys: (checking: boolean) => ({ checking }),
    }),
    reducers({
        checkingRunningSurveys: [
            false,
            {
                setCheckingRunningSurveys: (_, { checking }) => checking,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setSurveysOptIn: async ({ optIn }) => {
            if (!optIn) {
                actions.updateCurrentTeam({ surveys_opt_in: false })
                return
            }

            actions.setCheckingRunningSurveys(true)
            let untargetedSurveys: Survey[] | null
            try {
                untargetedSurveys = await loadUntargetedRunningSurveys(String(values.currentProjectId))
            } catch (error) {
                posthog.captureException(error)
                untargetedSurveys = null
            } finally {
                actions.setCheckingRunningSurveys(false)
            }

            if (untargetedSurveys?.length === 0) {
                actions.updateCurrentTeam({ surveys_opt_in: true })
                return
            }

            let confirmed = false
            LemonDialog.open({
                title: 'Show surveys to all users?',
                content: <SurveysOptInConfirmation untargetedSurveys={untargetedSurveys} />,
                primaryButton: {
                    children: 'Turn on surveys',
                    status: 'danger',
                    'data-attr': 'surveys-opt-in-confirm',
                    onClick: () => {
                        confirmed = true
                        actions.updateCurrentTeam({ surveys_opt_in: true })
                    },
                },
                secondaryButton: {
                    children: 'Cancel',
                    'data-attr': 'surveys-opt-in-cancel',
                },
                onAfterClose: () => {
                    // pinned: analytics event name and properties - renaming breaks dashboards
                    posthog.capture('surveys opt in confirmation', {
                        untargeted_survey_count: untargetedSurveys?.length ?? null,
                        confirmed,
                    })
                },
            })
        },
    })),
])
