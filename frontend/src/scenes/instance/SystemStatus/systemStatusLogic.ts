// Note: This logic does some heavy calculations - avoid connecting it outside of system status pages!
export const systemStatusLogic = kea<systemStatusLogicType>([
    path(['scenes', 'instance', 'SystemStatus', 'systemStatusLogic']),
    actions({
        setTab: (tab: InstanceStatusTabName) => ({ tab }),
        setOpenSections: (sections: string[]) => ({ sections }),
        updateInstanceSetting: (key: string, value: string) => ({ key, value }),
        deleteStoredInstanceSetting: (key: string) => ({ key }),
        updateInstanceSettingDone: true,
    }),
    loaders(() => ({
        systemStatus: [
            null as SystemStatus | null,
            {
                loadSystemStatus: async () => {
                    if (!isUserLoggedIn()) {
                        // If user is anonymous (i.e. viewing a shared dashboard logged out), don't load authenticated stuff
                        return null
                    }

                    if (preflightLogic.values.preflight?.cloud && !userLogic.values.user?.is_staff) {
                        return null
                    }

                    // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                    return (await api.get('api/instance_status')).results ?? null
                },
            },
        ],
        instanceSettings: [
            [] as InstanceSetting[],
            {
                loadInstanceSettings: async () => {
                    // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                    return (await api.get('api/instance_settings')).results ?? []
                },
            },
        ],
        queries: [
            null as SystemStatusQueriesResult | null,
            {
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                loadQueries: async () => (await api.get('api/instance_status/queries')).results,
            },
        ],
    })),
    reducers({
        tab: [
            'overview' as InstanceStatusTabName,
            {
                setTab: (_, { tab }) => tab,
            },
        ],
        error: [
            null as null | string,
            {
                loadSystemStatusFailure: (_, { error }) => error,
            },
        ],
        instanceSettingUpdating: [
            null as string | null,
            {
                updateInstanceSetting: (_, { key }) => key,
                deleteStoredInstanceSetting: (_, { key }) => key,
                updateInstanceSettingDone: () => null,
            },
        ],
        openSections: [
            ['0'] as string[],
            { persist: true },
            {
                setOpenSections: (_, { sections }) => sections,
            },
        ],
    }),
    selectors(() => ({
        overview: [
            (s) => [s.systemStatus],
            (status: SystemStatus | null): SystemStatusRow[] => (status ? status.overview : []),
        ],
        databaseInstanceSettings: [
            (s) => [s.instanceSettings],
            (instanceSettings: InstanceSetting[]): InstanceSetting[] =>
                instanceSettings.filter((item) => item.is_set_in_database && !item.editable),
        ],
        editableInstanceSettings: [
            (s) => [s.instanceSettings],
            (instanceSettings: InstanceSetting[]): InstanceSetting[] =>
                instanceSettings.filter((item) => item.editable),
        ],
    })),
    listeners(({ actions }) => ({
        setTab: ({ tab }: { tab: InstanceStatusTabName }) => {
            if (tab === 'metrics') {
                actions.loadQueries()
            }
        },
        updateInstanceSetting: async ({ key, value }) => {
            try {
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                await api.update(`api/instance_settings/${key}`, { value })
                // pinned: analytics event name, used to measure how often these settings change
                posthog.capture('instance setting change', { name: key, value })
                lemonToast.success(`${key} updated`)
                actions.loadInstanceSettings()
            } catch (error: any) {
                lemonToast.error(error?.detail ?? `Couldn't update ${key}. Check the value and try again.`)
            } finally {
                actions.updateInstanceSettingDone()
            }
        },
        deleteStoredInstanceSetting: async ({ key }) => {
            try {
                // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. No generated function covers this endpoint yet. Find out why the generated client skips it (no schema, no product tag, or excluded from the spec) and fix that first.
                await api.delete(`api/instance_settings/${key}`)
                lemonToast.success(`Deleted the stored value of ${key}`)
                actions.loadInstanceSettings()
            } catch (error: any) {
                lemonToast.error(error?.detail ?? `Couldn't delete the stored value of ${key}. Try again.`)
            } finally {
                actions.updateInstanceSettingDone()
            }
        },
    })),
    actionToUrl(({ values }) => ({
        setTab: () => '/instance/' + (values.tab === 'overview' ? 'status' : values.tab),
    })),
    urlToAction(({ actions, values }) => ({
        '/instance(/:tab)': ({ tab }: { tab?: InstanceStatusTabName }) => {
            const currentTab = tab && ['metrics', 'settings', 'staff_users'].includes(tab) ? tab : 'overview'
            if (currentTab !== values.tab) {
                actions.setTab(currentTab)
            }
        },
    })),
    events(({ actions }) => ({
        afterMount: () => {
            actions.loadSystemStatus()
        },
    })),
])
