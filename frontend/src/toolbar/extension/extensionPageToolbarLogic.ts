import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'

import { elementsLogic } from '~/toolbar/elements/elementsLogic'
import { currentPageLogic } from '~/toolbar/stats/currentPageLogic'
import { toolbarConfigLogic } from '~/toolbar/toolbarConfigLogic'
import type { ElementWithMetadata } from '~/toolbar/types'

import type { FragileSelectorResult } from '../utils/selectorQuality'
import type {
    InspectedElementInfo,
    PageToolCommands,
    PageToolName,
    PageToolbarCommand,
    PageToolbarInspectState,
    PageToolbarMode,
    PageToolbarState,
    PageToolbarTokens,
} from './pageToolbarBridge'

export type PageSessionCommand =
    | { type: 'set-mode'; mode: PageToolbarMode }
    | { type: 'set-tokens'; tokens: PageToolbarTokens }
    | { type: 'set-href'; href: string }

export type PageInspectCommand = { type: 'clear-selected-element' }

function inspectedElementInfo(meta: ElementWithMetadata | null): InspectedElementInfo | null {
    if (!meta) {
        return null
    }
    return {
        tagName: meta.element.tagName.toLowerCase(),
        actionStep: meta.actionStep ?? null,
        actions: (meta.actions ?? []).map(({ action }) => ({ id: action.id, name: action.name ?? null })),
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface extensionPageToolbarLogicValues {
    activeMeta:
        | (ElementWithMetadata & {
              selectorQuality: FragileSelectorResult | null
          })
        | null // elementsLogic
    activeMetaIsSelected: boolean // elementsLogic
    inspectEnabled: boolean // elementsLogic
    inspectState: PageToolbarInspectState
    mode: PageToolbarMode
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface extensionPageToolbarLogicActions {
    handleCommand: (message: PageToolbarCommand) => {
        message: PageToolbarCommand
    }
    setMode: (mode: PageToolbarMode) => {
        mode: PageToolbarMode
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface extensionPageToolbarLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        mode: (inspectEnabled: any) => PageToolbarMode
        inspectState: (activeMeta: any, activeMetaIsSelected: any) => PageToolbarInspectState
    }
}

export type extensionPageToolbarLogicType = MakeLogicType<
    extensionPageToolbarLogicValues,
    extensionPageToolbarLogicActions,
    Record<string, any>,
    extensionPageToolbarLogicMeta
>

/** Runs in the content script. Mount it after `toolbarConfigLogic`, because the connected logics read its tokens. */
export const extensionPageToolbarLogic = kea<extensionPageToolbarLogicType>([
    path(['toolbar', 'extension', 'extensionPageToolbarLogic']),
    connect(() => ({
        values: [elementsLogic, ['inspectEnabled', 'activeMeta', 'activeMetaIsSelected']],
    })),
    actions({
        handleCommand: (message: PageToolbarCommand) => ({ message }),
        setMode: (mode: PageToolbarMode) => ({ mode }),
    }),
    selectors({
        mode: [
            (s) => [s.inspectEnabled],
            (inspectEnabled: boolean): PageToolbarMode => (inspectEnabled ? 'inspect' : 'none'),
        ],
        inspectState: [
            (s) => [s.activeMeta, s.activeMetaIsSelected],
            (activeMeta: ElementWithMetadata | null, activeMetaIsSelected: boolean): PageToolbarInspectState => ({
                element: inspectedElementInfo(activeMeta),
                isSelected: activeMetaIsSelected,
            }),
        ],
    }),
    listeners(({ actions }) => ({
        setMode: ({ mode }) => {
            if (mode === 'inspect') {
                elementsLogic.actions.enableInspect()
            } else {
                elementsLogic.actions.disableInspect()
            }
        },
        handleCommand: ({ message }) => {
            const handlers: { [Tool in PageToolName]: (command: PageToolCommands[Tool]) => void } = {
                session: (command) => {
                    if (command.type === 'set-mode') {
                        actions.setMode(command.mode)
                    } else if (command.type === 'set-href') {
                        currentPageLogic.actions.setHref(command.href)
                    } else {
                        const { accessToken, refreshToken, clientId } = command.tokens
                        toolbarConfigLogic.actions.setOAuthTokens(accessToken, refreshToken, clientId)
                    }
                },
                inspect: () => elementsLogic.actions.setSelectedElement(null),
            }
            ;(handlers[message.tool] as (command: PageToolbarCommand['command']) => void)(message.command)
        },
    })),
])

/** Every slice comes from a memoized selector, so the host posts only the slices whose reference changed. */
export function getPageToolbarState(): PageToolbarState {
    const { mode, inspectState } = extensionPageToolbarLogic.values
    return {
        mode,
        inspect: inspectState,
    }
}
