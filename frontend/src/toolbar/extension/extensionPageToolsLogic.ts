/**
 * Drives work on the active tab from the popup. The popup calls the PostHog API with the user's session, and the
 * content script only draws on the page and reads its DOM. Mount this logic only when the tab is ready for the toolbar.
 */
export const extensionPageToolsLogic = kea<extensionPageToolsLogicType>([
    path(['toolbar', 'extension', 'extensionPageToolsLogic']),
    connect(() => ({
        values: [extensionPopupLogic, ['tabId', 'tabUrl', 'uiHost', 'dataAttributes']],
    })),
    actions({
        setSelectedElement: (selectedElement: SelectedElement | null) => ({ selectedElement }),
        clearSelectedElement: true,
        copySelector: true,
        setFlagOverride: (flagKey: string, value: FlagValue | null) => ({ flagKey, value }),
        trackPageTool: (tool: PageToolKey, properties?: Record<string, unknown>) => ({ tool, properties }),
    }),
    reducers({
        selectedElement: [
            null as SelectedElement | null,
            {
                setSelectedElement: (_, { selectedElement }) => selectedElement,
                clearSelectedElement: () => null,
            },
        ],
    }),
    loaders(({ values }) => {
        const command = async (run: (tabId: number) => Promise<ContentStatus>): Promise<ContentStatus> =>
            values.tabId === null ? IDLE_CONTENT_STATUS : await run(values.tabId)
        const pageFlags = async (flags: Record<string, FlagValue> | null): Promise<PageFlagOverrides | null> =>
            values.tabId === null ? null : await runPageFlagOverrides(values.tabId, flags)

        return {
            contentStatus: [
                IDLE_CONTENT_STATUS,
                {
                    loadContentStatus: async () => await command(getContentStatus),
                    showHeatmap: async () => {
                        const { status, data } = await fetchWithSession(
                            values.uiHost,
                            `/api/element/stats/?${new URLSearchParams({
                                properties: JSON.stringify([
                                    {
                                        key: '$current_url',
                                        value: values.tabUrl,
                                        operator: PropertyOperator.Exact,
                                        type: PropertyFilterType.Event,
                                    },
                                ]),
                                date_from: HEATMAP_DATE_FROM,
                                paginate_response: 'true',
                                limit: String(ELEMENT_STATS_LIMIT),
                                data_attributes: values.dataAttributes.join(','),
                            })}`
                        )
                        const elementStats = (data as { results?: ElementsEventType[] } | null)?.results
                        if (status !== 200 || !Array.isArray(elementStats)) {
                            throw new Error('Could not load heatmap data')
                        }
                        return await command((tabId) =>
                            sendContentCommand(tabId, {
                                type: 'show-heatmap',
                                elementStats,
                                dataAttributes: values.dataAttributes,
                            })
                        )
                    },
                    hideHeatmap: async () =>
                        await command((tabId) => sendContentCommand(tabId, { type: 'hide-heatmap' })),
                    startElementSelection: async () =>
                        await command((tabId) =>
                            sendContentCommand(tabId, {
                                type: 'start-element-selection',
                                dataAttributes: values.dataAttributes,
                            })
                        ),
                },
            ],
            userFlags: [
                null as CombinedFeatureFlagAndValueType[] | null,
                {
                    loadUserFlags: async () => {
                        const { status, data } = await fetchWithSession(values.uiHost, MY_FLAGS_PATH)
                        return status === 200 && Array.isArray(data)
                            ? (data as CombinedFeatureFlagAndValueType[])
                            : null
                    },
                },
            ],
            pageFlags: [
                null as PageFlagOverrides | null,
                {
                    loadPageFlags: async () => await pageFlags(null),
                    setFlagOverride: async ({ flagKey, value }) => {
                        const overrides = { ...values.pageFlags?.overrides }
                        if (value === null) {
                            delete overrides[flagKey]
                        } else {
                            overrides[flagKey] = value
                        }
                        return await pageFlags(overrides)
                    },
                    clearFlagOverrides: async () => await pageFlags({}),
                },
            ],
        }
    }),
    reducers({
        heatmapError: [false, { showHeatmap: () => false, showHeatmapFailure: () => true, hideHeatmap: () => false }],
    }),
    selectors({
        flagRows: [
            (s) => [s.userFlags, s.pageFlags],
            (userFlags: CombinedFeatureFlagAndValueType[] | null, pageFlags: PageFlagOverrides | null): FlagRow[] =>
                (userFlags ?? []).map(({ feature_flag, value }) => ({
                    key: feature_flag.key,
                    value,
                    override: pageFlags?.overrides[feature_flag.key],
                    variants: (feature_flag.filters?.multivariate?.variants ?? []).map(({ key }) => key),
                })),
        ],
        selectedElementForPage: [
            (s) => [s.selectedElement, s.tabUrl],
            (selectedElement: SelectedElement | null, tabUrl: string | null | undefined): SelectedElement | null =>
                selectedElement && samePage(selectedElement.pageUrl, tabUrl) ? selectedElement : null,
        ],
    }),
    listeners(({ actions, values }) => ({
        trackPageTool: ({ tool, properties }) => {
            // pinned: analytics event name
            toolbarPosthogJS.capture('toolbar extension page tool used', { tool, ...properties })
        },
        showHeatmapSuccess: ({ contentStatus }) => {
            actions.trackPageTool('heatmap', { matched_element_count: contentStatus.heatmapElementCount })
        },
        startElementSelectionSuccess: () => {
            actions.trackPageTool('element-selection')
            // The user picks on the page, and a click there closes the popup anyway.
            window.close()
        },
        clearSelectedElement: () => {
            void clearStoredSelectedElement()
        },
        copySelector: () => {
            const selector = values.selectedElementForPage?.actionStep.selector
            if (selector) {
                void navigator.clipboard.writeText(selector)
            }
        },
        setFlagOverrideSuccess: ({ payload }) => {
            actions.trackPageTool('flag-override', { action: payload?.value === null ? 'remove' : 'set' })
        },
        clearFlagOverridesSuccess: () => {
            actions.trackPageTool('flag-override', { action: 'clear' })
        },
    })),
    afterMount(({ actions, cache }) => {
        actions.loadContentStatus()
        actions.loadUserFlags()
        actions.loadPageFlags()
        void getStoredSelectedElement().then(actions.setSelectedElement)
        cache.removeSelectedElementListener = onStoredSelectedElementChange(actions.setSelectedElement)
    }),
    beforeUnmount(({ cache }) => {
        cache.removeSelectedElementListener?.()
    }),
])
