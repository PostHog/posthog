// The floating toolbar's heatmap defaults to the same range.
const HEATMAP_DATE_FROM = '-7d'

// The content script matches rows in one pass, so the popup loads one page instead of the toolbar's pagination.
const ELEMENT_STATS_LIMIT = 5000

// The floating toolbar loads the same list through toolbarApi.featureFlags.myFlags.
const MY_FLAGS_PATH = '/api/projects/@current/feature_flags/my_flags/'

// pinned: sent as the `tool` property of `toolbar extension page tool used`
type PageToolKey = 'heatmap' | 'element-selection' | 'flag-override'

export type FlagValue = string | boolean

export interface FlagRow {
    key: string
    /** The value PostHog evaluates for the signed-in user, without overrides. */
    value: FlagValue
    override: FlagValue | undefined
    /** Empty for a boolean flag. */
    variants: string[]
}

function samePage(pageUrl: string, tabUrl: string | null | undefined): boolean {
    if (!tabUrl) {
        return false
    }
    try {
        const page = new URL(pageUrl)
        const tab = new URL(tabUrl)
        return page.origin === tab.origin && page.pathname === tab.pathname
    } catch {
        return false
    }
}

