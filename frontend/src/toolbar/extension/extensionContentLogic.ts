export type extensionContentLogicType = MakeLogicType<
    extensionContentLogicValues,
    extensionContentLogicActions,
    Record<string, any>,
    extensionContentLogicMeta
>

/** Runs in the content script. Draws on the page and reads the page DOM, but never calls the PostHog API. */
export const extensionContentLogic = kea<extensionContentLogicType>([
    path(['toolbar', 'extension', 'extensionContentLogic']),
    actions({
        handleCommand: (command: ContentCommand) => ({ command }),
        startElementSelection: (dataAttributes: string[]) => ({ dataAttributes }),
        stopElementSelection: true,
        expectInspectedElement: (dataAttributes: string[]) => ({ dataAttributes }),
        setHoverElement: (element: HTMLElement | null) => ({ element }),
        selectElement: (element: HTMLElement) => ({ element }),
        setConfirmedElement: (element: HTMLElement | null) => ({ element }),
        showHeatmap: (elementStats: ElementsEventType[], dataAttributes: string[]) => ({
            elementStats,
            dataAttributes,
        }),
        setHeatmapElements: (elements: CountedHTMLElement[]) => ({ elements }),
        hideHeatmap: true,
        updateRects: true,
    }),
    reducers({
        selecting: [false, { startElementSelection: () => true, stopElementSelection: () => false }],
        dataAttributes: [
            [] as string[],
            {
                startElementSelection: (_, { dataAttributes }) => dataAttributes,
                expectInspectedElement: (_, { dataAttributes }) => dataAttributes,
            },
        ],
        hoverElement: [
            null as HTMLElement | null,
            { setHoverElement: (_, { element }) => element, stopElementSelection: () => null },
        ],
        confirmedElement: [
            null as HTMLElement | null,
            { setConfirmedElement: (_, { element }) => element, startElementSelection: () => null },
        ],
        heatmapElements: [
            null as CountedHTMLElement[] | null,
            { setHeatmapElements: (_, { elements }) => elements, hideHeatmap: () => null },
        ],
        rectUpdateCounter: [0, { updateRects: (counter) => counter + 1 }],
    }),
    selectors({
        // rectUpdateCounter is an input so that rects follow scroll, resize and sticky elements.
        hoverRect: [(s) => [s.hoverElement, s.rectUpdateCounter], rectForConnectedElement],
        confirmedRect: [(s) => [s.confirmedElement, s.rectUpdateCounter], rectForConnectedElement],
        heatmapOverlayElements: [
            (s) => [s.heatmapElements, s.rectUpdateCounter],
            (heatmapElements: CountedHTMLElement[] | null): ElementWithMetadata[] =>
                (heatmapElements ?? [])
                    .filter(({ element }) => element.isConnected)
                    .map((counted) => ({ ...counted, rect: getRectForElement(counted.element), visible: true })),
        ],
        highestClickCount: [
            (s) => [s.heatmapElements],
            (heatmapElements: CountedHTMLElement[] | null): number =>
                (heatmapElements ?? []).reduce((highest, { count }) => Math.max(highest, count), 0),
        ],
        status: [
            (s) => [s.selecting, s.heatmapElements],
            (selecting: boolean, heatmapElements: CountedHTMLElement[] | null): ContentStatus => ({
                selecting,
                heatmapElementCount: heatmapElements ? heatmapElements.length : null,
            }),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        handleCommand: ({ command }) => {
            switch (command.type) {
                case 'start-element-selection':
                    actions.startElementSelection(command.dataAttributes)
                    return
                case 'stop-element-selection':
                    actions.stopElementSelection()
                    return
                case 'expect-inspected-element':
                    actions.expectInspectedElement(command.dataAttributes)
                    return
                case 'show-heatmap':
                    actions.showHeatmap(command.elementStats, command.dataAttributes)
                    return
                case 'hide-heatmap':
                    actions.hideHeatmap()
                    return
                case 'get-status':
                    return
            }
        },
        startElementSelection: () => {
            const logicCache = cache as ContentLogicCache
            if (logicCache.selectionListeners) {
                return
            }
            const block = (event: Event): void => {
                event.preventDefault()
                event.stopImmediatePropagation()
            }
            const selectionListeners: { type: string; listener: (event: Event) => void }[] = [
                ...BLOCKED_POINTER_EVENTS.map((type) => ({ type, listener: block })),
                {
                    type: 'mousemove',
                    listener: (event) => {
                        const element = selectableElementFromEvent(event)
                        if (element !== values.hoverElement) {
                            actions.setHoverElement(element)
                        }
                    },
                },
                {
                    type: 'click',
                    listener: (event) => {
                        block(event)
                        const element = selectableElementFromEvent(event) ?? values.hoverElement
                        if (element) {
                            actions.selectElement(element)
                        }
                    },
                },
                {
                    type: 'keydown',
                    listener: (event) => {
                        if ((event as KeyboardEvent).key === 'Escape') {
                            block(event)
                            actions.stopElementSelection()
                        }
                    },
                },
            ]
            for (const { type, listener } of selectionListeners) {
                // Capture on window runs before every page listener.
                window.addEventListener(type, listener, true)
            }
            logicCache.selectionListeners = selectionListeners
        },
        stopElementSelection: () => {
            const logicCache = cache as ContentLogicCache
            for (const { type, listener } of logicCache.selectionListeners ?? []) {
                window.removeEventListener(type, listener, true)
            }
            logicCache.selectionListeners = undefined
        },
        expectInspectedElement: () => {
            // The DevTools panel dispatches the event on $0 from the page's world right after this command.
            // The listener takes one event, so a page script can't keep sending elements.
            const logicCache = cache as ContentLogicCache
            if (logicCache.inspectedElementListener) {
                window.removeEventListener(INSPECTED_ELEMENT_EVENT, logicCache.inspectedElementListener, true)
            }
            const listener = (event: Event): void => {
                window.removeEventListener(INSPECTED_ELEMENT_EVENT, listener, true)
                logicCache.inspectedElementListener = undefined
                // The user picked this exact element in DevTools, so it isn't trimmed to a clickable parent.
                // Autocapture records HTML elements, so an SVG pick uses its closest HTML ancestor.
                let element: EventTarget | null = event.composedPath()[0] ?? null
                while (element instanceof Element && !(element instanceof HTMLElement)) {
                    element = element.parentElement
                }
                if (element instanceof HTMLElement) {
                    actions.selectElement(element)
                }
            }
            window.addEventListener(INSPECTED_ELEMENT_EVENT, listener, true)
            logicCache.inspectedElementListener = listener
        },
        selectElement: async ({ element }, breakpoint) => {
            const actionStep = elementToActionStep(element, values.dataAttributes)
            actions.stopElementSelection()
            actions.setConfirmedElement(element)
            await setStoredSelectedElement({
                pageUrl: window.location.href,
                actionStep,
                selectorQuality: actionStep.selector ? checkSelectorFragility(actionStep.selector) : null,
            })
            await breakpoint(SELECTED_CONFIRMATION_MS)
            actions.setConfirmedElement(null)
        },
        showHeatmap: ({ elementStats, dataAttributes }) => {
            actions.setHeatmapElements(matchElementStatsToElements(elementStats, { dataAttributes }))
        },
    })),
    afterMount(({ actions, cache }) => {
        const logicCache = cache as ContentLogicCache
        logicCache.onViewportChange = () => {
            if (logicCache.animationFrame === undefined) {
                logicCache.animationFrame = window.requestAnimationFrame(() => {
                    logicCache.animationFrame = undefined
                    actions.updateRects()
                })
            }
        }
        window.addEventListener('scroll', logicCache.onViewportChange, { capture: true, passive: true })
        window.addEventListener('resize', logicCache.onViewportChange, { passive: true })
    }),
    beforeUnmount(({ actions, cache }) => {
        const logicCache = cache as ContentLogicCache
        actions.stopElementSelection()
        if (logicCache.inspectedElementListener) {
            window.removeEventListener(INSPECTED_ELEMENT_EVENT, logicCache.inspectedElementListener, true)
        }
        if (logicCache.onViewportChange) {
            window.removeEventListener('scroll', logicCache.onViewportChange, { capture: true })
            window.removeEventListener('resize', logicCache.onViewportChange)
        }
        if (logicCache.animationFrame !== undefined) {
            window.cancelAnimationFrame(logicCache.animationFrame)
        }
    }),
])
