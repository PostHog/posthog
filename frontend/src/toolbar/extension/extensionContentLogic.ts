import { MakeLogicType, actions, afterMount, beforeUnmount, kea, listeners, path, reducers, selectors } from 'kea'

import { matchElementStatsToElements } from '~/toolbar/elements/matchElementStats'
import { CountedHTMLElement, ElementRect, ElementWithMetadata, ElementsEventType } from '~/toolbar/types'
import { elementToActionStep, getRectForElement, trimElement } from '~/toolbar/utils'
import { checkSelectorFragility } from '~/toolbar/utils/selectorQuality'

import { ContentCommand, ContentStatus, INSPECTED_ELEMENT_EVENT } from './contentBridge'
import { setStoredSelectedElement } from './extensionBrowser'

const SELECTED_CONFIRMATION_MS = 2500

// Page handlers can act on these before the click arrives, so selection mode keeps them from the page too.
const BLOCKED_POINTER_EVENTS = ['pointerdown', 'pointerup', 'mousedown', 'mouseup']

function selectableElementFromEvent(event: Event): HTMLElement | null {
    // composedPath reaches into open shadow roots, where event.target stops at the host.
    const target = event.composedPath()[0]
    return target instanceof HTMLElement ? trimElement(target) : null
}

function rectForConnectedElement(element: HTMLElement | null): ElementRect | null {
    return element?.isConnected ? getRectForElement(element) : null
}

interface ContentLogicCache {
    selectionListeners?: { type: string; listener: (event: Event) => void }[]
    inspectedElementListener?: (event: Event) => void
    onViewportChange?: () => void
    animationFrame?: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface extensionContentLogicValues {
    confirmedElement: HTMLElement | null
    confirmedRect: ElementRect | null
    dataAttributes: string[]
    heatmapElements: CountedHTMLElement[] | null
    heatmapOverlayElements: ElementWithMetadata[]
    highestClickCount: number
    hoverElement: HTMLElement | null
    hoverRect: ElementRect | null
    rectUpdateCounter: number
    selecting: boolean
    status: ContentStatus
}

