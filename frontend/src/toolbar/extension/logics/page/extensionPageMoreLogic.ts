// The floating toolbar's PII masking stylesheet has another id, so the two never remove each other's.
const PII_MASKING_STYLESHEET_ID = 'posthog-toolbar-extension-pii-masking'

// The panel shows the screenshot at its own width, so a small copy keeps the message light.
const SCREENSHOT_PREVIEW_WIDTH = 640

type ScreenshotResult = PageToolbarMoreState['screenshot']['result']

async function previewDataUrl(objectUrl: string): Promise<string> {
    const image = new Image()
    image.src = objectUrl
    await image.decode()
    const scale = Math.min(1, SCREENSHOT_PREVIEW_WIDTH / image.naturalWidth)
    const canvas = document.createElement('canvas')
    canvas.width = Math.round(image.naturalWidth * scale)
    canvas.height = Math.round(image.naturalHeight * scale)
    canvas.getContext('2d')?.drawImage(image, 0, 0, canvas.width, canvas.height)
    return canvas.toDataURL('image/jpeg', 0.8)
}

