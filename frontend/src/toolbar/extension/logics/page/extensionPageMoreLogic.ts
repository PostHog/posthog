/** Runs in the content script for the toolbar's "More" menu tools. */
export const extensionPageMoreLogic = kea<extensionPageMoreLogicType>([
    path(['toolbar', 'extension', 'extensionPageMoreLogic']),
    props({} as ExtensionPageMoreLogicProps),
    connect(() => ({
        values: [
            toolbarConfigLogic,
            ['posthog'],
            screenshotUploadLogic,
            [
                'isTakingScreenshot',
                'isModalOpen',
                'eventName',
                'eventDefinitions',
                'eventDefinitionsLoading',
                'selectedDefinition',
                'uploadResultLoading',
            ],
        ],
        actions: [
            screenshotUploadLogic,
            [
                'takeScreenshot',
                'takeScreenshotFailure',
                'openModal',
                'closeModal',
                'submitUpload',
                'submitUploadSuccess',
                'submitUploadFailure',
            ],
        ],
    })),
    actions({
        openMore: true,
        handleCommand: (command: PageMoreCommand) => ({ command }),
        setPiiMaskingEnabled: (enabled: boolean) => ({ enabled }),
        setPiiMaskingColor: (color: string) => ({ color }),
        setScreenshotPreview: (dataUrl: string | null) => ({ dataUrl }),
    }),
    loaders(({ props }) => ({
        debugInfo: [
            null as PageDebugInfo | null,
            {
                loadDebugInfo: async () => (await props.posthogBridge?.readDebugInfo()) ?? null,
            },
        ],
    })),
    reducers({
        piiMaskingEnabled: [false, { persist: true }, { setPiiMaskingEnabled: (_, { enabled }) => enabled }],
        piiMaskingColor: [
            DEFAULT_PII_MASKING_COLOR as string,
            { persist: true },
            { setPiiMaskingColor: (_, { color }) => color },
        ],
        // The host sends the preview in its own message, so it stays out of the state the panel gets on every change.
        screenshotPreview: [
            null as string | null,
            { setScreenshotPreview: (_, { dataUrl }) => dataUrl, closeModal: () => null },
        ],
        screenshotResult: [
            null as ScreenshotResult,
            {
                takeScreenshot: () => null,
                submitUpload: () => null,
                submitUploadSuccess: () => ({ status: 'uploaded' }),
                submitUploadFailure: (_, { error }) => ({ status: 'failed', error }),
                takeScreenshotFailure: (_, { error }) => ({ status: 'failed', error }),
            },
        ],
    }),
    selectors({
        piiWarnings: [
            (s) => [s.posthog, s.piiMaskingEnabled],
            (posthog: PostHog | null, piiMaskingEnabled: boolean): string[] =>
                posthog && piiMaskingEnabled ? getPiiMaskingWarnings(posthog) : [],
        ],
        suggestions: [
            (s) => [s.eventDefinitions],
            (eventDefinitions: EventDefinition[]): PageToolbarMoreState['screenshot']['suggestions'] =>
                eventDefinitions.map(({ id, name }) => ({ id, name })),
        ],
        pageState: [
            (s) => [
                s.debugInfo,
                s.debugInfoLoading,
                s.piiMaskingEnabled,
                s.piiMaskingColor,
                s.piiWarnings,
                s.isTakingScreenshot,
                s.isModalOpen,
                s.eventName,
                s.suggestions,
                s.eventDefinitionsLoading,
                s.selectedDefinition,
                s.uploadResultLoading,
                s.screenshotResult,
            ],
            (
                debugInfo: PageDebugInfo | null,
                debugInfoLoading: boolean,
                piiMaskingEnabled: boolean,
                piiMaskingColor: string,
                piiWarnings: string[],
                isTakingScreenshot: boolean,
                isModalOpen: boolean,
                eventName: string,
                suggestions: PageToolbarMoreState['screenshot']['suggestions'],
                eventDefinitionsLoading: boolean,
                selectedDefinition: EventDefinition | null,
                uploadResultLoading: boolean,
                screenshotResult: ScreenshotResult
            ): PageToolbarMoreState => ({
                debugInfo,
                debugInfoLoading,
                piiMaskingEnabled,
                piiMaskingColor,
                piiWarnings,
                screenshot: {
                    taking: isTakingScreenshot,
                    open: isModalOpen,
                    eventName,
                    suggestions,
                    suggestionsLoading: eventDefinitionsLoading,
                    selectedEventId: selectedDefinition?.id ?? null,
                    uploading: uploadResultLoading,
                    result: screenshotResult,
                },
            }),
        ],
    }),
    listeners(({ actions, values }) => {
        const applyPiiMasking = (): void =>
            applyPiiMaskingStylesheet(
                PII_MASKING_STYLESHEET_ID,
                values.piiMaskingEnabled,
                values.piiMaskingColor,
                values.posthog
            )
        return {
            openMore: () => {
                actions.loadDebugInfo()
            },
            setPiiMaskingEnabled: applyPiiMasking,
            setPiiMaskingColor: applyPiiMasking,
            openModal: async ({ previewUrl }) => {
                try {
                    actions.setScreenshotPreview(await previewDataUrl(previewUrl))
                } catch {
                    actions.takeScreenshotFailure("Couldn't read the screenshot")
                }
            },
            handleCommand: ({ command }) => {
                const screenshot = screenshotUploadLogic.actions
                switch (command.type) {
                    case 'reload-debug-info':
                        actions.loadDebugInfo()
                        return
                    case 'set-pii-masking':
                        actions.setPiiMaskingEnabled(command.enabled)
                        return
                    case 'set-pii-masking-color':
                        actions.setPiiMaskingColor(command.color)
                        return
                    case 'take-screenshot':
                        screenshot.takeScreenshot()
                        return
                    case 'set-screenshot-event-name':
                        screenshot.setEventName(command.name)
                        return
                    case 'select-screenshot-event': {
                        const definition = values.eventDefinitions.find(({ id }) => id === command.id)
                        if (definition) {
                            screenshot.selectEvent(definition)
                        }
                        return
                    }
                    case 'upload-screenshot':
                        screenshot.submitUpload(null)
                        return
                    case 'close-screenshot':
                        screenshot.closeModal()
                        return
                }
            },
        }
    }),
    afterMount(({ values, cache }) => {
        cache.disposables.add(() => {
            // A persisted preview comes back on with the page tools, like the floating toolbar's.
            applyPiiMaskingStylesheet(
                PII_MASKING_STYLESHEET_ID,
                values.piiMaskingEnabled,
                values.piiMaskingColor,
                values.posthog
            )
            return () => applyPiiMaskingStylesheet(PII_MASKING_STYLESHEET_ID, false, values.piiMaskingColor, null)
        }, 'piiMasking')
    }),
])
