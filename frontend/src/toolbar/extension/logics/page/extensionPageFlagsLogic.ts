import type { PostHog } from 'posthog-js'

import { readFlagOverrides } from '~/toolbar/shared/flags/flagComparison'
import {
    FlagComparison,
    FlagComparisonCapture,
    FlagComparisonFailureReason,
    comparisonFailureReason,
    flagComparisonLogic,
} from '~/toolbar/shared/flags/flagComparisonLogic'
import { FlagInfo, toFlagInfo } from '~/toolbar/shared/flags/flagInfo'
import { flagsToolbarLogic, flagsToolbarLogicValues } from '~/toolbar/shared/flags/flagsToolbarLogic'
import { toolbarConfigLogic } from '~/toolbar/shared/toolbarConfigLogic'

import type { FeatureFlagType } from '../../../../types'
import { PageFlagMutationStatus, restoreFlagsOnUnload } from '../../messaging/pagePosthogBridge'
import type { PageToolbarFlagsState } from '../../messaging/pageToolbarBridge'
import { jpegDataUrl } from './jpegDataUrl'

export type PageFlagsCommand =
    | { type: 'set-flag-override'; flagKey: string; value: string | boolean }
    | { type: 'remove-flag-override'; flagKey: string }
    | { type: 'save-flag-payload'; flagKey: string; draftPayload: string }
    | { type: 'clear-flag-overrides' }
    | { type: 'reload-flags' }
    | { type: 'impersonate-flags'; distinctId: string }
    | { type: 'clear-flag-impersonation' }
    | { type: 'compare-flag'; flagKey: string }
    | { type: 'close-flag-comparison' }

// These never write overrides, so they can't clash with the comparison's restore and run while one is in progress.
const COMMANDS_DURING_COMPARISON: PageFlagsCommand['type'][] = ['reload-flags', 'close-flag-comparison']

// The side panel shows a capture a few hundred pixels wide, and Chrome refuses a port message over 64 MiB. A full-width
// capture of a long page costs megabytes per state, so the panel gets a smaller copy.
const COMPARISON_MAX_WIDTH = 1280
// Chrome refuses the whole message past 64 MiB, and the panel would wait for a comparison that never arrives. The
// labels and sizes next to the images take a few bytes.
const COMPARISON_MAX_MESSAGE_LENGTH = 60 * 1024 * 1024

