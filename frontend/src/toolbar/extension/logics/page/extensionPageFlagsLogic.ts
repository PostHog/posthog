export type extensionPageFlagsLogicType = MakeLogicType<
    extensionPageFlagsLogicValues,
    extensionPageFlagsLogicActions,
    Record<string, any>,
    extensionPageFlagsLogicMeta
>

export const extensionPageFlagsLogic = kea<extensionPageFlagsLogicType>([
    path(['toolbar', 'extension', 'extensionPageFlagsLogic']),
    connect(() => ({
        values: [
            flagsToolbarLogic,
            ['filteredFlags', 'userFlagsLoading', 'countFlagsOverridden', 'impersonatedDistinctId', 'payloadErrors'],
            toolbarConfigLogic,
            ['posthog'],
            flagComparisonLogic,
            ['comparingFlagKey as runningComparisonFlagKey'],
        ],
        actions: [flagComparisonLogic, ['compareFlag', 'compareFlagSuccess', 'compareFlagFailure']],
    })),
    actions({
        openFlags: true,
        handleCommand: (command: PageFlagsCommand) => ({ command }),
        setFlagMutationStatus: (status: PageFlagMutationStatus) => ({ status }),
        setComparison: (comparison: FlagComparison | null) => ({ comparison }),
        setComparisonError: (error: FlagComparisonError | null) => ({ error }),
    }),
    reducers({
        flagMutationStatus: [
            { pending: false, error: null, revision: 0 } as PageFlagMutationStatus,
            { setFlagMutationStatus: (_, { status }) => status },
        ],
        // The comparison with its captures as data URLs, which the host sends the panel in its own message.
        comparison: [
            null as FlagComparison | null,
            { compareFlag: () => null, setComparison: (_, { comparison }) => comparison },
        ],
        comparisonError: [
            null as FlagComparisonError | null,
            {
                compareFlag: () => null,
                compareFlagFailure: (_, { errorObject }) =>
                    errorObject instanceof FlagOverridesChangedError ? 'overrides-changed' : 'capture-failed',
                setComparisonError: (_, { error }) => error,
            },
        ],
        // The shared logic finishes before the captures become data URLs, and the panel waits for those too.
        convertingFlagKey: [
            null as string | null,
            {
                compareFlagSuccess: (_, { comparison }) => comparison.flagKey,
                setComparison: () => null,
                setComparisonError: () => null,
            },
        ],
    }),
    selectors({
        flags: [(s) => [s.filteredFlags], (filteredFlags: FilteredFlag[]): FlagInfo[] => filteredFlags.map(toFlagInfo)],
        comparingFlagKey: [
            (s) => [s.runningComparisonFlagKey, s.convertingFlagKey],
            (runningComparisonFlagKey: string | null, convertingFlagKey: string | null): string | null =>
                runningComparisonFlagKey ?? convertingFlagKey,
        ],
        pageState: [
            (s) => [
                s.posthog,
                s.userFlagsLoading,
                s.flags,
                s.countFlagsOverridden,
                s.impersonatedDistinctId,
                s.payloadErrors,
                s.flagMutationStatus,
                s.comparingFlagKey,
                s.comparisonError,
            ],
            (
                posthog: PostHog | null,
                userFlagsLoading: boolean,
                flags: FlagInfo[],
                countFlagsOverridden: number,
                impersonatedDistinctId: string | null,
                payloadErrors: Record<string, string | null>,
                flagMutationStatus: PageFlagMutationStatus,
                comparingFlagKey: string | null,
                comparisonError: FlagComparisonError | null
            ): PageToolbarFlagsState => ({
                available: !!posthog,
                loading: userFlagsLoading,
                flags,
                countFlagsOverridden,
                impersonatedDistinctId,
                payloadErrors,
                mutationPending: flagMutationStatus.pending,
                mutationError: flagMutationStatus.error,
                mutationRevision: flagMutationStatus.revision,
                comparingFlagKey,
                comparisonError,
            }),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        openFlags: () => {
            const posthog: PostHog | null = values.posthog
            const flags = flagsToolbarLogic.actions
            if (posthog && !cache.subscribed) {
                cache.subscribed = true
                posthog.onFeatureFlags(flags.setFeatureFlagValueFromPostHogClient)
                const variants = posthog.featureFlags.getFlagVariants()
                flags.setFeatureFlagValueFromPostHogClient(Object.keys(variants), variants)
            }
            flags.getUserFlags()
            flags.checkLocalOverrides()
        },
        setFlagMutationStatus: () => {
            // The page agent reports the overrides the page applied, which can differ from the ones the logic sent.
            flagsToolbarLogic.actions.checkLocalOverrides()
        },
        compareFlagSuccess: async ({ comparison }) => {
            restoreFlagsOnUnload(null)
            try {
                const captures = await Promise.all(
                    comparison.captures.map(async (capture) => ({ ...capture, url: await jpegDataUrl(capture.url) }))
                )
                actions.setComparison({ ...comparison, captures })
            } catch {
                actions.setComparisonError('capture-failed')
            } finally {
                // The data URLs replace the object URLs, so this frees the page's copies.
                flagComparisonLogic.actions.closeComparison()
            }
        },
        compareFlagFailure: () => {
            restoreFlagsOnUnload(null)
        },
        handleCommand: ({ command }) => {
            const flags = flagsToolbarLogic.actions
            if (values.comparingFlagKey && !COMMANDS_DURING_COMPARISON.includes(command.type)) {
                // A second panel on the tab can send a change mid-comparison, and the comparison's restore would undo it.
                // The new revision lets that panel send changes again once the comparison ends.
                if (command.type !== 'compare-flag') {
                    actions.setFlagMutationStatus({
                        ...values.flagMutationStatus,
                        revision: values.flagMutationStatus.revision + 1,
                    })
                }
                return
            }
            switch (command.type) {
                case 'set-flag-override':
                    flags.setOverriddenUserFlag(command.flagKey, command.value)
                    return
                case 'remove-flag-override':
                    flags.deleteOverriddenUserFlag(command.flagKey)
                    return
                case 'save-flag-payload':
                    flags.setDraftPayload(command.flagKey, command.draftPayload)
                    flags.savePayloadOverride(command.flagKey)
                    if (values.payloadErrors[command.flagKey]) {
                        // Invalid JSON never reaches the page's posthog-js, so the change ends here with its error.
                        actions.setFlagMutationStatus({
                            ...values.flagMutationStatus,
                            revision: values.flagMutationStatus.revision + 1,
                        })
                    }
                    return
                case 'clear-flag-overrides':
                    flags.clearAllOverrides()
                    return
                case 'reload-flags':
                    flags.getUserFlags()
                    flags.checkLocalOverrides()
                    return
                case 'impersonate-flags':
                    flags.loadFlagsForDistinctId(command.distinctId)
                    return
                case 'clear-flag-impersonation':
                    flags.clearImpersonation()
                    return
                case 'compare-flag': {
                    const flag = values.flags.find(({ key }) => key === command.flagKey)
                    if (!flag) {
                        return
                    }
                    if (values.posthog) {
                        restoreFlagsOnUnload(readFlagOverrides(values.posthog) ?? {})
                    }
                    actions.compareFlag(flag)
                    return
                }
                case 'close-flag-comparison':
                    actions.setComparison(null)
                    actions.setComparisonError(null)
                    return
            }
        },
    })),
])
