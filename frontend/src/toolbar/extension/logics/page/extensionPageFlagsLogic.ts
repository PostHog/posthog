    filteredFlags: {
        currentValue: boolean | string
        feature_flag: FeatureFlagType
        hasOverride: boolean
        hasVariants: boolean
        payloadOverride: any
        value: boolean | string
    }[] // flagsToolbarLogic
    impersonatedDistinctId: string | null // flagsToolbarLogic
    payloadErrors: Record<string, string | null> // flagsToolbarLogic
    userFlagsLoading: boolean // flagsToolbarLogic
    posthog: PostHog | null // toolbarConfigLogic
    flagMutationStatus: PageFlagMutationStatus
