import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import { actionsLogic } from '~/toolbar/shared/actions/actionsLogic'
import { actionsTabLogic } from '~/toolbar/shared/actions/actionsTabLogic'

import type { ActionType, ElementType } from '../../../../types'
import type { ActionForm } from '../../../shared/types'
import type { ActionSaveResult, PageToolbarActionsState } from '../../messaging/pageToolbarBridge'

export type PageActionsCommand =
    | { type: 'select-action'; id: number | null }
    | { type: 'new-action'; fromSelectedElement: boolean }
    | { type: 'set-action-form'; form: ActionForm }
    | { type: 'inspect-for-action-step'; index: number | null }
    | { type: 'save-action' }

