export type extensionPageActionsLogicType = MakeLogicType<
    extensionPageActionsLogicValues,
    extensionPageActionsLogicActions,
    Record<string, any>,
    extensionPageActionsLogicMeta
>

export const extensionPageActionsLogic = kea<extensionPageActionsLogicType>([
    path(['toolbar', 'extension', 'extensionPageActionsLogic']),
    connect(() => ({
        values: [
            actionsLogic,
            ['sortedActions', 'allActionsLoading'],
            actionsTabLogic,
            ['actionForm', 'actionFormElementsChains', 'inspectingElement', 'isActionFormSubmitting'],
        ],
        actions: [
            actionsTabLogic,
            ['actionCreatedSuccess', 'submitActionFormFailure', 'selectAction', 'newAction', 'inspectElementSelected'],
        ],
    })),
    actions({
        handleCommand: (command: PageActionsCommand) => ({ command }),
        setSaveResult: (saveResult: ActionSaveResult | null) => ({ saveResult }),
    }),
    reducers({
        saveResult: [
            null as ActionSaveResult | null,
            {
                setSaveResult: (_, { saveResult }) => saveResult,
                actionCreatedSuccess: (_, { action }) => ({
                    status: 'saved' as const,
                    actionId: action.id,
                    name: action.name ?? null,
                }),
                submitActionFormFailure: (_, { error }) => ({
                    status: 'failed' as const,
                    error: error?.message || 'Unknown error',
                }),
                selectAction: () => null,
                newAction: () => null,
            },
        ],
        // The panel edits its own copy of the form, and takes the page's copy only when the page changed it.
        formRevision: [
            0,
            {
                selectAction: (revision) => revision + 1,
                newAction: (revision) => revision + 1,
                inspectElementSelected: (revision) => revision + 1,
            },
        ],
    }),
    selectors({
        actionsList: [
            (s) => [s.sortedActions],
            (sortedActions: ActionType[]): PageToolbarActionsState['actions'] =>
                sortedActions.map(({ id, name }) => ({ id, name: name ?? null })),
        ],
        pageState: [
            (s) => [
                s.allActionsLoading,
                s.actionsList,
                // kea-typegen drops the 'new' literal when it copies a connected value's type, so read the selector.
                actionsTabLogic.selectors.selectedActionId,
                s.actionForm,
                s.formRevision,
                s.actionFormElementsChains,
                s.inspectingElement,
                s.isActionFormSubmitting,
                s.saveResult,
            ],
            (
                allActionsLoading: boolean,
                actionsList: PageToolbarActionsState['actions'],
                selectedActionId: number | 'new' | null,
                actionForm: ActionForm,
                formRevision: number,
                actionFormElementsChains: Record<number, ElementType[]>,
                inspectingElement: number | null,
                isActionFormSubmitting: boolean,
                saveResult: ActionSaveResult | null
            ): PageToolbarActionsState => ({
                allActionsLoading,
                actions: actionsList,
                selectedActionId,
                actionForm,
                formRevision,
                actionFormElementsChains,
                inspectingElement,
                saving: isActionFormSubmitting,
                saveResult,
            }),
        ],
    }),
    listeners(({ actions }) => ({
        handleCommand: ({ command }) => {
            switch (command.type) {
                case 'select-action':
                    actionsTabLogic.actions.selectAction(command.id)
                    return
                case 'set-action-form':
                    actionsTabLogic.actions.setActionFormValues(command.form)
                    return
                case 'inspect-for-action-step':
                    actionsTabLogic.actions.inspectForElementWithIndex(command.index)
                    return
                case 'save-action':
                    actions.setSaveResult(null)
                    actionsTabLogic.actions.submitActionForm()
                    return
            }
        },
    })),
])
