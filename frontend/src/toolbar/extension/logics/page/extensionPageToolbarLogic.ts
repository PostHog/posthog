export type PageSessionCommand =
    | { type: 'set-mode'; mode: PageToolbarMode }
    | { type: 'set-tokens'; tokens: PageToolbarTokens }
    | { type: 'set-href'; href: string }

export type PageInspectCommand = { type: 'clear-selected-element' }

export type PageSelectorsCommand = { type: 'count-selectors'; selectors: string[] }

export interface ExtensionPageToolbarLogicProps {
    /** Null when the page has no `window.posthog`. */
    posthogBridge: PagePosthogBridge | null
}

type PanelMenuMode = Extract<PageToolbarMode, 'flags' | 'events' | 'web-vitals' | 'more'>

const PANEL_MENU_MODES: PanelMenuMode[] = ['flags', 'events', 'web-vitals', 'more']

// The panel asks about the selectors its open form shows, so a short list covers it.
const MAX_COUNTED_SELECTORS = 20

// Recounts the selectors once the page stops changing for this long.
const SELECTOR_RECOUNT_DEBOUNCE_MS = 300

function countMatches(selectors: string[]): Record<string, SelectorMatchCounts | null> {
    return Object.fromEntries(selectors.map((selector) => [selector, countSelectorMatches(selector)]))
}

function inspectedElementInfo(meta: ElementWithMetadata | null): InspectedElementInfo | null {
    if (!meta) {
        return null
    }
    return {
        tagName: meta.element.tagName.toLowerCase(),
        actionStep: meta.actionStep ?? null,
        stats: meta.position
            ? {
                  count: meta.count ?? 0,
                  clickCount: meta.clickCount ?? 0,
                  rageclickCount: meta.rageclickCount ?? 0,
                  deadclickCount: meta.deadclickCount ?? 0,
                  rank: meta.position,
              }
            : null,
        actions: (meta.actions ?? []).map(({ action }) => ({ id: action.id, name: action.name ?? null })),
    }
}

