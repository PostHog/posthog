export type PageHeatmapCommand =
    | { type: 'set-wildcard-href'; href: string }
    | { type: 'auto-wildcard-href' }
    | { type: 'set-auto-wildcard-enabled'; enabled: boolean }
    | { type: 'set-common-filters'; filters: CommonFilters }
    | { type: 'patch-heatmap-filters'; filters: Partial<HeatmapFilters> }
    | { type: 'set-clickmaps-enabled'; enabled: boolean }
    | { type: 'set-match-links-by-href'; matchLinksByHref: boolean }
    | { type: 'set-fixed-position-mode'; mode: HeatmapFixedPositionMode }
    | { type: 'set-color-palette'; palette: string | null }
    | { type: 'load-all-element-stats' }
    | { type: 'stop-loading-all-element-stats' }
    | { type: 'start-area-selection' }
    | { type: 'cancel-area-selection' }
    | { type: 'clear-area-filter' }
    | { type: 'highlight-counted-element'; index: number | null }
    | { type: 'select-counted-element'; index: number }
    | { type: 'save-heatmap' }

