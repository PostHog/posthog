/** Runs in the content script, next to the toolbar's heatmap logics. */
export const extensionPageHeatmapLogic = kea<extensionPageHeatmapLogicType>([
    path(['toolbar', 'extension', 'extensionPageHeatmapLogic']),
    connect(() => ({
        values: [
            currentPageLogic,
            ['wildcardHref', 'autoWildcardEnabled', 'wildcardHrefTooSpecific', 'wildcardHrefEndsWithSlash'],
            heatmapToolbarMenuLogic,
            [
                'commonFilters',
                'heatmapFilters',
                'heatmapColorPalette',
                'heatmapFixedPositionMode',
                'viewportRange',
                'rawHeatmapLoading',
                'scrollDepthPosthogJsError',
                'clickmapsEnabled',
                'elementStatsLoading',
                'elementsLoading',
                'processingProgress',
                'matchLinksByHref',
                'countedElements',
                'clickCount',
                'canLoadMoreElementStats',
                'loadedElementStatsCount',
                'loadingAllElementStats',
                'areaSelectionActive',
                'heatmapAreaFilter',
            ],
            toolbarConfigLogic,
            ['posthog'],
            heatmapCaptureLogic,
            ['captureResultLoading', 'captureProgress', 'captureSummary'],
        ],
        actions: [heatmapCaptureLogic, ['saveToPostHogSuccess', 'saveToPostHogFailure']],
    })),
    actions({
        handleCommand: (command: PageHeatmapCommand) => ({ command }),
    }),
    reducers({
        saveOutcome: [
            null as SaveOutcome | null,
            {
                saveToPostHogSuccess: (_, { captureResult }) =>
                    captureResult ? { status: 'saved', shortId: captureResult.short_id } : null,
                saveToPostHogFailure: (_, { error }) => ({ status: 'failed', error }),
            },
        ],
    }),
    selectors({
        heatmapsCollection: [
            (s) => [s.posthog],
            (posthog: PostHog | null): PageToolbarHeatmapState['heatmapsCollection'] =>
                !posthog
                    ? 'unknown'
                    : !posthog.heatmaps
                      ? 'unsupported'
                      : posthog.heatmaps.isEnabled
                        ? 'enabled'
                        : 'disabled',
        ],
        // Reading `innerText` lays out the page, so it runs only when the counted elements change.
        countedElementInfos: [
            (s) => [s.countedElements],
            (countedElements: CountedHTMLElement[]): PageToolbarHeatmapState['countedElements'] =>
                countedElements.map(({ element, count }) => ({
                    text: element.innerText?.trim().substring(0, MAX_ELEMENT_TEXT_LENGTH) ?? '',
                    tagName: element.tagName.toLowerCase(),
                    count,
                })),
        ],
        saveResult: [
            (s) => [s.saveOutcome, s.captureSummary],
            (
                saveOutcome: SaveOutcome | null,
                captureSummary: { savedWidths: number; totalWidths: number } | null
            ): HeatmapSaveResult | null =>
                saveOutcome?.status === 'saved'
                    ? {
                          ...saveOutcome,
                          savedWidths: captureSummary?.savedWidths ?? 0,
                          totalWidths: captureSummary?.totalWidths ?? 0,
                      }
                    : saveOutcome,
        ],
        // kea types a selector with up to about a dozen inputs, so the slice comes from three smaller ones.
        filtersState: [
            (s) => [
                s.wildcardHref,
                s.autoWildcardEnabled,
                s.wildcardHrefTooSpecific,
                s.wildcardHrefEndsWithSlash,
                s.commonFilters,
                s.heatmapFilters,
                s.heatmapColorPalette,
                s.heatmapFixedPositionMode,
                s.viewportRange,
                s.rawHeatmapLoading,
            ],
            (
                wildcardHref: string,
                autoWildcardEnabled: boolean,
                wildcardHrefTooSpecific: boolean,
                wildcardHrefEndsWithSlash: boolean,
                commonFilters: CommonFilters,
                heatmapFilters: HeatmapFilters,
                heatmapColorPalette: string | null,
                heatmapFixedPositionMode: HeatmapFixedPositionMode,
                viewportRange: { min: number; max: number },
                rawHeatmapLoading: boolean
            ): HeatmapFiltersState => ({
                wildcardHref,
                autoWildcardEnabled,
                wildcardHrefTooSpecific,
                wildcardHrefEndsWithSlash,
                commonFilters,
                heatmapFilters,
                heatmapColorPalette,
                heatmapFixedPositionMode,
                viewportRange,
                rawHeatmapLoading,
            }),
        ],
        clickmapState: [
            (s) => [
                s.heatmapsCollection,
                s.scrollDepthPosthogJsError,
                s.clickmapsEnabled,
                s.elementStatsLoading,
                s.elementsLoading,
                s.processingProgress,
                s.matchLinksByHref,
                s.countedElementInfos,
                s.clickCount,
                s.canLoadMoreElementStats,
            ],
            (
                heatmapsCollection: PageToolbarHeatmapState['heatmapsCollection'],
                scrollDepthPosthogJsError: ScrollDepthPosthogJsError,
                clickmapsEnabled: boolean,
                elementStatsLoading: boolean,
                elementsLoading: boolean,
                processingProgress: PageToolbarHeatmapState['processingProgress'],
                matchLinksByHref: boolean,
                countedElementInfos: PageToolbarHeatmapState['countedElements'],
                clickCount: number,
                canLoadMoreElementStats: boolean
            ): HeatmapClickmapState => ({
                heatmapsCollection,
                scrollDepthPosthogJsError,
                clickmapsEnabled,
                clickmapLoading: elementStatsLoading || elementsLoading,
                processingProgress,
                matchLinksByHref,
                countedElements: countedElementInfos,
                clickCount,
                canLoadMoreElementStats,
            }),
        ],
        areaAndSaveState: [
            (s) => [
                s.loadedElementStatsCount,
                s.loadingAllElementStats,
                s.areaSelectionActive,
                s.heatmapAreaFilter,
                s.captureResultLoading,
                s.captureProgress,
                s.saveResult,
            ],
            (
                loadedElementStatsCount: number,
                loadingAllElementStats: boolean,
                areaSelectionActive: boolean,
                heatmapAreaFilter: { element: HTMLElement; selector: string | null } | null,
                captureResultLoading: boolean,
                captureProgress: PageToolbarHeatmapState['saveProgress'],
                saveResult: HeatmapSaveResult | null
            ): HeatmapAreaAndSaveState => ({
                loadedElementStatsCount,
                loadingAllElementStats,
                areaSelectionActive,
                areaFilter: heatmapAreaFilter
                    ? { selector: heatmapAreaFilter.selector, tagName: heatmapAreaFilter.element.tagName.toLowerCase() }
                    : null,
                savingHeatmap: captureResultLoading,
                saveProgress: captureProgress,
                saveResult,
            }),
        ],
        pageState: [
            (s) => [s.filtersState, s.clickmapState, s.areaAndSaveState],
            (
                filtersState: HeatmapFiltersState,
                clickmapState: HeatmapClickmapState,
                areaAndSaveState: HeatmapAreaAndSaveState
            ): PageToolbarHeatmapState => ({
                ...filtersState,
                ...clickmapState,
                ...areaAndSaveState,
            }),
        ],
    }),
    listeners(({ values }) => ({
        handleCommand: ({ command }) => {
            const heatmap = heatmapToolbarMenuLogic.actions
            const page = currentPageLogic.actions
            switch (command.type) {
                case 'set-wildcard-href':
                    page.setWildcardHref(command.href)
                    return
                case 'auto-wildcard-href':
                    page.autoWildcardHref()
                    return
                case 'set-auto-wildcard-enabled':
                    page.setAutoWildcardEnabled(command.enabled)
                    return
                case 'set-common-filters':
                    heatmap.setCommonFilters(command.filters)
                    return
                case 'patch-heatmap-filters':
                    heatmap.patchHeatmapFilters(command.filters)
                    return
                case 'set-clickmaps-enabled':
                    heatmap.toggleClickmapsEnabled(command.enabled)
                    return
                case 'set-match-links-by-href':
                    heatmap.setMatchLinksByHref(command.matchLinksByHref)
                    return
                case 'set-fixed-position-mode':
                    heatmap.setHeatmapFixedPositionMode(command.mode)
                    return
                case 'set-color-palette':
                    heatmap.setHeatmapColorPalette(command.palette)
                    return
                case 'load-all-element-stats':
                    heatmap.startLoadingAllElementStats()
                    return
                case 'stop-loading-all-element-stats':
                    heatmap.stopLoadingAllElementStats()
                    return
                case 'start-area-selection':
                    heatmap.startAreaSelection()
                    return
                case 'cancel-area-selection':
                    heatmap.cancelAreaSelection()
                    return
                case 'clear-area-filter':
                    heatmap.selectHeatmapAreaFilter(null)
                    return
                case 'highlight-counted-element':
                    elementsLogic.actions.setHighlightElement(
                        command.index === null ? null : (values.countedElements[command.index]?.element ?? null)
                    )
                    return
                case 'select-counted-element': {
                    const element = values.countedElements[command.index]?.element
                    if (element) {
                        element.scrollIntoView({ block: 'center', behavior: 'smooth' })
                        elementsLogic.actions.setSelectedElement(element)
                    }
                    return
                }
                case 'save-heatmap':
                    heatmapCaptureLogic.actions.saveToPostHog()
                    return
            }
        },
    })),
])
