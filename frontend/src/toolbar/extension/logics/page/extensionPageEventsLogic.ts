/** Runs in the content script, from the first time the user opens the events tool. */
export const extensionPageEventsLogic = kea<extensionPageEventsLogicType>([
    path(['toolbar', 'extension', 'extensionPageEventsLogic']),
    props({} as ExtensionPageEventsLogicProps),
    connect(() => ({
        values: [
            eventDebugMenuLogic,
            [
                'selectedEventTypes',
                'hidePostHogProperties',
                'hidePostHogFlags',
                'relativeTimestamps',
                'isPaused',
                'bufferedCount',
                'totalEventsCount',
                'activeFilteredEvents',
                'searchFilteredEventsCount',
                'pinnedEvents',
                'unpinnedEvents',
                'expandedEvent',
                'expandedProperties',
                'events',
                'exportableEvents',
            ],
            toolbarConfigLogic,
            ['posthog'],
        ],
    })),
    actions({
        handleCommand: (command: PageEventsCommand) => ({ command }),
        setOpen: (open: boolean) => ({ open }),
    }),
    reducers({
        open: [true, { setOpen: (_, { open }) => open }],
    }),
    selectors({
        rows: [
            (s) => [s.open, s.pinnedEvents, s.unpinnedEvents],
            (open: boolean, pinnedEvents: EventType[], unpinnedEvents: EventType[]): DebugEventRow[] => {
                // A closed debugger keeps collecting, but sends no rows until it opens again.
                if (!open) {
                    return []
                }
                const pinnedRows = pinnedEvents.slice(0, MAX_PANEL_EVENT_ROWS).map((event) => eventRow(event, true))
                const unpinnedRows = unpinnedEvents
                    .slice(0, MAX_PANEL_EVENT_ROWS - pinnedRows.length)
                    .map((event) => eventRow(event, false))
                return [...pinnedRows, ...unpinnedRows]
            },
        ],
        expandedEventPayload: [
            (s) => [s.open, s.expandedEvent, s.events],
            (open: boolean, expandedEventId: string | null, events: EventType[]): Record<string, unknown> | null => {
                const event = open && expandedEventId ? events.find(({ uuid }) => uuid === expandedEventId) : undefined
                return event
                    ? { event: event.event, timestamp: event.timestamp, properties: event.properties, uuid: event.uuid }
                    : null
            },
        ],
        pageState: [
            (s) => [
                s.posthog,
                s.open,
                s.selectedEventTypes,
                s.hidePostHogProperties,
                s.hidePostHogFlags,
                s.relativeTimestamps,
                s.isPaused,
                s.bufferedCount,
                s.totalEventsCount,
                s.activeFilteredEvents,
                s.searchFilteredEventsCount,
                s.rows,
                s.expandedEvent,
                s.expandedProperties,
                s.expandedEventPayload,
            ],
            (
                posthog: PostHog | null,
                open: boolean,
                selectedEventTypes: EventCategory[],
                hidePostHogProperties: boolean,
                hidePostHogFlags: boolean,
                relativeTimestamps: boolean,
                isPaused: boolean,
                bufferedCount: number,
                totalEventsCount: number,
                activeFilteredEvents: EventType[],
                searchFilteredEventsCount: Record<EventCategory, number>,
                rows: DebugEventRow[],
                expandedEvent: string | null,
                expandedProperties: Record<string, unknown> | unknown[],
                expandedEventPayload: Record<string, unknown> | null
            ): PageToolbarEventsState => ({
                available: !!posthog,
                selectedEventTypes,
                hidePostHogProperties,
                hidePostHogFlags,
                relativeTimestamps,
                isPaused,
                bufferedCount,
                totalCount: totalEventsCount,
                filteredCount: activeFilteredEvents.length,
                countsByType: searchFilteredEventsCount,
                rows,
                expandedEventId: expandedEvent ?? null,
                expandedProperties: open && !Array.isArray(expandedProperties) ? expandedProperties : {},
                expandedEventPayload,
            }),
        ],
    }),
    listeners(({ values }) => ({
        handleCommand: ({ command }) => {
            const debug = eventDebugMenuLogic.actions
            switch (command.type) {
                case 'set-events-search':
                    debug.setSearchText(command.searchText)
                    return
                case 'set-event-type-enabled':
                    debug.setSelectedEventType(command.eventType, command.enabled)
                    return
                case 'set-hide-posthog-properties':
                    debug.setHidePostHogProperties(command.hide)
                    return
                case 'set-hide-posthog-flags':
                    debug.setHidePostHogFlags(command.hide)
                    return
                case 'expand-event':
                    debug.markExpanded(command.uuid)
                    return
                case 'toggle-pinned-event':
                    debug.togglePinnedEvent(command.uuid)
                    return
                case 'toggle-relative-timestamps':
                    debug.toggleRelativeTimestamps()
                    return
                case 'toggle-events-paused':
                    debug.togglePaused()
                    return
                case 'clear-events':
                    debug.clearEvents()
                    return
                case 'export-events':
                    // The download starts from the page, which keeps every event. The panel only has the newest rows.
                    downloadEventsAsJson(values.exportableEvents)
                    return
            }
        },
    })),
    subscriptions(({ props }) => ({
        selectedEventTypes: (selectedEventTypes: EventCategory[]) => {
            // Snapshot events carry the page's recording, so the page sends their payload only to a debugger that shows them.
            props.posthogBridge?.setForwardSnapshotPayloads(selectedEventTypes.includes('snapshot'))
        },
    })),
])
