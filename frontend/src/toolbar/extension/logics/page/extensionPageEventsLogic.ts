// Every change to the events slice carries the rows, so the panel gets the newest events only. The debugger keeps more.
const MAX_PANEL_EVENT_ROWS = 200

export type PageEventsCommand =
    | { type: 'set-events-search'; searchText: string }
    | { type: 'set-event-type-enabled'; eventType: EventCategory; enabled: boolean }
    | { type: 'set-hide-posthog-properties'; hide: boolean }
    | { type: 'set-hide-posthog-flags'; hide: boolean }
    | { type: 'expand-event'; uuid: string | null }
    | { type: 'toggle-pinned-event'; uuid: string }
    | { type: 'toggle-relative-timestamps' }
    | { type: 'toggle-events-paused' }
    | { type: 'clear-events' }
    | { type: 'export-events' }

export interface ExtensionPageEventsLogicProps {
    /** Null when the page has no `window.posthog`. */
    posthogBridge: PagePosthogBridge | null
}

