export const extensionPageExperimentsLogic = kea<extensionPageExperimentsLogicType>([
    path(['toolbar', 'extension', 'extensionPageExperimentsLogic']),
    connect(() => ({
        values: [
            experimentsLogic,
            ['sortedExperiments', 'allExperimentsLoading'],
            experimentsTabLogic,
            [
                'experimentForm',
                'selectedVariant',
                'selectedElementType',
                'inspectingElement',
                'addVariantAvailable',
                'removeVariantAvailable',
                'isExperimentFormSubmitting',
            ],
            toolbarConfigLogic,
            ['posthog'],
        ],
        actions: [
            experimentsTabLogic,
            [
                'selectExperiment',
                'newExperiment',
                'inspectElementSelected',
                'addNewVariant',
                'removeVariant',
                'addNewTransformation',
                'removeElement',
                'submitExperimentForm',
                'submitExperimentFormFailure',
            ],
            experimentsLogic,
            ['updateExperiment'],
        ],
    })),
    actions({
        handleCommand: (command: PageExperimentsCommand) => ({ command }),
        closeExperiments: true,
    }),
    reducers({
        formRevision: [
            0,
            {
                selectExperiment: (revision) => revision + 1,
                newExperiment: (revision) => revision + 1,
                inspectElementSelected: (revision) => revision + 1,
                addNewVariant: (revision) => revision + 1,
                removeVariant: (revision) => revision + 1,
                addNewTransformation: (revision) => revision + 1,
                removeElement: (revision) => revision + 1,
            },
        ],
        saveResult: [
            null as ExperimentSaveResult | null,
            {
                updateExperiment: (_, { experiment }) => ({
                    status: 'saved' as const,
                    experimentId: Number(experiment.id),
                    name: experiment.name ?? null,
                }),
                submitExperimentFormFailure: (_, { error }) => ({
                    status: 'failed' as const,
                    error: error?.message || 'Check the form and try again.',
                }),
                // A save clears the selection, which must keep the result for the list to show.
                selectExperiment: (saveResult, { id }) => (id === null ? saveResult : null),
                newExperiment: () => null,
                submitExperimentForm: () => null,
                closeExperiments: () => null,
            },
        ],
    }),
    selectors({
        experimentsList: [
            (s) => [s.sortedExperiments],
            (sortedExperiments: WebExperiment[]): PageToolbarExperimentsState['experiments'] =>
                sortedExperiments.map(({ id, name }) => ({ id: Number(id), name: name ?? null })),
        ],
        experimentFormDraft: [
            (s) => [s.experimentForm],
            (experimentForm: WebExperimentForm): ExperimentFormDraft => ({
                name: experimentForm.name,
                variants: experimentForm.variants ?? {},
            }),
        ],
        pageState: [
            (s) => [
                s.allExperimentsLoading,
                s.experimentsList,
                s.posthog,
                // kea-typegen drops the 'new' literal when it copies a connected value's type, so read the selector.
                experimentsTabLogic.selectors.selectedExperimentId,
                s.experimentFormDraft,
                s.formRevision,
                s.selectedVariant,
                s.selectedElementType,
                s.inspectingElement,
                s.addVariantAvailable,
                s.removeVariantAvailable,
                s.isExperimentFormSubmitting,
                s.saveResult,
            ],
            (
                allExperimentsLoading: boolean,
                experimentsList: PageToolbarExperimentsState['experiments'],
                posthog: PostHog | null,
                selectedExperimentId: number | 'new' | 'web' | null,
                experimentFormDraft: ExperimentFormDraft,
                formRevision: number,
                selectedVariant: string,
                selectedElementType: ElementSelectorType,
                inspectingElement: number | null,
                addVariantAvailable: boolean | undefined,
                removeVariantAvailable: boolean | undefined,
                isExperimentFormSubmitting: boolean,
                saveResult: ExperimentSaveResult | null
            ): PageToolbarExperimentsState => ({
                loading: allExperimentsLoading,
                experiments: experimentsList,
                webExperimentsDisabled: !!posthog?.config?.disable_web_experiments,
                selectedExperimentId: selectedExperimentId === 'web' ? null : selectedExperimentId,
                experimentForm: experimentFormDraft,
                formRevision,
                selectedVariant,
                selectedElementType,
                inspectingElement,
                addVariantAvailable: !!addVariantAvailable,
                removeVariantAvailable: !!removeVariantAvailable,
                saving: isExperimentFormSubmitting,
                saveResult,
            }),
        ],
    }),
    listeners(({ values }) => ({
        closeExperiments: () => {
            experimentsTabLogic.actions.selectExperiment(null)
            experimentsTabLogic.actions.hideButtonExperiments()
        },
        handleCommand: ({ command }) => {
            const tab = experimentsTabLogic.actions
            switch (command.type) {
                case 'select-experiment':
                    if (command.id === 'new') {
                        tab.newExperiment()
                    } else {
                        tab.selectExperiment(command.id)
                    }
                    return
                case 'set-experiment-form':
                    tab.setExperimentFormValues(command.form)
                    // Shows the edited HTML and CSS on the page as the user types.
                    tab.applyVariant(values.selectedVariant)
                    return
                case 'select-experiment-variant':
                    if (command.variant === null) {
                        tab.selectVariant('')
                        // The form keeps the original HTML, so leaving the experiment can still restore it.
                        restoreOriginalHtmlState(values.experimentForm.original_html_state)
                        return
                    }
                    tab.selectVariant(command.variant)
                    tab.applyVariant(command.variant)
                    return
                case 'add-experiment-variant':
                    tab.addNewVariant()
                    return
                case 'remove-experiment-variant':
                    tab.removeVariant(command.variant)
                    tab.applyVariant('control')
                    return
                case 'add-experiment-transform':
                    tab.addNewTransformation(command.variant)
                    return
                case 'remove-experiment-transform':
                    tab.removeElement(command.variant, command.index)
                    tab.applyVariant(values.selectedVariant)
                    return
                case 'set-experiment-element-type':
                    tab.selectElementType(command.elementType)
                    return
                case 'inspect-for-experiment-transform':
                    tab.selectVariant(command.variant)
                    tab.inspectForElementWithIndex(command.variant, values.selectedElementType, command.index)
                    return
                case 'set-experiment-transform-selector': {
                    const element = querySelectorInDocument(command.selector)
                    if (element) {
                        tab.inspectElementSelected(element, command.variant, command.index, command.selector)
                    }
                    return
                }
                case 'save-experiment':
                    tab.submitExperimentForm()
                    return
            }
        },
    })),
])
