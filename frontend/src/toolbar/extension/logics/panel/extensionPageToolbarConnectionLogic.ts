export const extensionPageToolbarConnectionLogic = kea<extensionPageToolbarConnectionLogicType>([
    path(['toolbar', 'extension', 'extensionPageToolbarConnectionLogic']),
    connect(() => ({
        values: [
            extensionPanelLogic,
            ['tabId', 'tabUrl', 'uiHost', 'dataAttributes', 'projectUrl'],
            extensionAuthLogic,
            ['tokens'],
        ],
        actions: [extensionPanelLogic, ['setTab'], extensionAuthLogic, ['setTokens', 'updateTokens', 'tokensExpired']],
    })),
    actions({
        connectPage: true,
        setConnectionStatus: (status: PageToolbarConnectionStatus) => ({ status }),
        receiveState: (state: PageToolbarState | null) => ({ state }),
        receivePatch: (patch: Partial<PageToolbarState>) => ({ patch }),
        receiveScreenshotPreview: (dataUrl: string) => ({ dataUrl }),
        sendCommand: (message: PageToolbarCommand) => ({ message }),
        setMode: (mode: PageToolbarMode) => ({ mode }),
        setWildcardHref: (href: string) => ({ href }),
        openHeatmapInPostHog: (shortId: string) => ({ shortId }),
        requestSelectorCount: (selector: string) => ({ selector }),
    }),
    reducers({
        connectionStatus: [
            'idle' as PageToolbarConnectionStatus,
            { setConnectionStatus: (_, { status }) => status, connectPage: () => 'connecting' },
        ],
        // A patch keeps every slice it doesn't carry, so a component that reads one slice skips unrelated messages.
        pageToolbarState: [
            null as PageToolbarState | null,
            {
                receiveState: (_, { state }) => state,
                receivePatch: (state, { patch }) => (state ? { ...state, ...patch } : state),
                setTab: () => null,
            },
        ],
        screenshotPreview: [
            null as string | null,
            { receiveScreenshotPreview: (_, { dataUrl }) => dataUrl, receiveState: () => null, setTab: () => null },
        ],
        // The page echoes the URL back a moment later. Until then the input shows what the user typed, so a fast typist
        // doesn't lose characters to an older echo.
        wildcardHrefDraft: [
            null as string | null,
            {
                setWildcardHref: (_, { href }) => href,
                receivePatch: (draft, { patch }) => (patch.heatmap?.wildcardHref === draft ? null : draft),
                setTab: () => null,
            },
        ],
        // The page loses its tools when it reloads, so the panel turns the mode the user picked back on.
        wantedMode: [
            'none' as PageToolbarMode,
            {
                setMode: (_, { mode }) => mode,
                receiveState: (mode, { state }) => state?.mode ?? mode,
                receivePatch: (mode, { patch }) => patch.mode ?? mode,
            },
        ],
        requestedSelectors: [
            [] as string[],
            {
                requestSelectorCount: (selectors, { selector }) =>
                    selectors.includes(selector) ? selectors : [...selectors, selector].slice(-MAX_REQUESTED_SELECTORS),
            },
        ],
    }),
    selectors({
        mode: [
            (s) => [s.pageToolbarState, s.wantedMode],
            (pageToolbarState: PageToolbarState | null, wantedMode: PageToolbarMode): PageToolbarMode =>
                pageToolbarState?.mode ?? wantedMode,
        ],
        inspect: [
            (s) => [s.pageToolbarState],
            (pageToolbarState: PageToolbarState | null) => pageToolbarState?.inspect ?? null,
        ],
        heatmap: [
            (s) => [s.pageToolbarState],
            (pageToolbarState: PageToolbarState | null) => pageToolbarState?.heatmap ?? null,
        ],
        webVitals: [
            (s) => [s.pageToolbarState],
            (pageToolbarState: PageToolbarState | null) => pageToolbarState?.webVitals ?? null,
        ],
        selectedActionId: [
            (s) => [s.pageToolbarState],
            (pageToolbarState: PageToolbarState | null) => pageToolbarState?.actions.selectedActionId ?? null,
        ],
        selectedExperimentId: [
            (s) => [s.pageToolbarState],
            (pageToolbarState: PageToolbarState | null) => pageToolbarState?.experiments.selectedExperimentId ?? null,
        ],
        selectorCounter: [
            (s) => [s.pageToolbarState],
            (pageToolbarState: PageToolbarState | null): Pick<SelectorMatchCounter, 'count'> => ({
                count: (selector, scope = 'deep') => {
                    const counts = pageToolbarState?.selectorCounts[selector]
                    return counts ? counts[scope] : counts
                },
            }),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const post = (message: PageToolbarRequest): void => {
            cache.port?.postMessage(message)
        }
        const sendSelectors = (): void => {
            if (values.requestedSelectors.length > 0) {
                actions.sendCommand({
                    tool: 'selectors',
                    command: { type: 'count-selectors', selectors: values.requestedSelectors },
                })
            }
        }
        return {
            connectPage: async (_, breakpoint) => {
                cache.port?.disconnect()
                cache.port = null
                const { tabId, tabUrl, tokens } = values
                if (tabId === null || !tabUrl || !tokens) {
                    actions.setConnectionStatus('idle')
                    return
                }
                try {
                    await Promise.all([ensureContentScript(tabId), injectPageAgent(tabId)])
                } catch {
                    actions.setConnectionStatus('failed')
                    return
                }
                breakpoint()
                const port: ExtensionPort = connectToPageToolbar(tabId)
                cache.port = port
                cache.portTabId = tabId
                port.onMessage.addListener((message) => {
                    if (!isPageToolbarMessage(message) || cache.port !== port) {
                        return
                    }
                    if (message.type === 'state') {
                        actions.receiveState(message.state)
                    } else if (message.type === 'patch') {
                        actions.receivePatch(message.patch)
                    } else if (message.type === 'screenshot-preview') {
                        actions.receiveScreenshotPreview(message.dataUrl)
                    } else if (message.type === 'tokens') {
                        actions.updateTokens(message.tokens)
                    } else if (message.type === 'token-expired') {
                        actions.tokensExpired()
                    }
                })
                // A new document has no content script, so the port closes when the tab loads another page.
                port.onDisconnect.addListener(() => {
                    if (cache.port === port) {
                        cache.port = null
                        actions.setConnectionStatus('idle')
                        actions.receiveState(null)
                    }
                })
                post({
                    type: 'start',
                    session: { ...tokens, uiHost: values.uiHost, dataAttributes: values.dataAttributes },
                    href: tabUrl,
                })
                if (values.wantedMode !== 'none') {
                    actions.sendCommand({ tool: 'session', command: { type: 'set-mode', mode: values.wantedMode } })
                }
                // A fresh content script knows nothing about the selectors the open form counts.
                sendSelectors()
                actions.setConnectionStatus('connected')
            },
            setWildcardHref: ({ href }) => {
                actions.sendCommand({ tool: 'heatmap', command: { type: 'set-wildcard-href', href } })
            },
            sendCommand: ({ message }) => {
                post(message)
            },
            setMode: ({ mode }) => {
                if (mode !== 'none') {
                    capturePageToolUsed(mode)
                }
                actions.sendCommand({ tool: 'session', command: { type: 'set-mode', mode } })
            },
            setTab: ({ tabId, tabUrl }) => {
                // A single-page app changes the URL in the same document, so the page tools keep running there.
                if (cache.port && cache.portTabId === tabId && tabUrl) {
                    actions.sendCommand({ tool: 'session', command: { type: 'set-href', href: tabUrl } })
                    return
                }
                actions.connectPage()
            },
            setTokens: ({ tokens }) => {
                if (!tokens) {
                    return
                }
                if (cache.port) {
                    actions.sendCommand({ tool: 'session', command: { type: 'set-tokens', tokens } })
                } else {
                    actions.connectPage()
                }
            },
            requestSelectorCount: async (_, breakpoint) => {
                await breakpoint(50)
                sendSelectors()
            },
            openHeatmapInPostHog: ({ shortId }) => {
                void openTab(values.projectUrl(urls.heatmap(shortId)))
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.connectPage()
    }),
    beforeUnmount(({ cache }) => {
        cache.port?.disconnect()
        cache.port = null
    }),
])
