/**
 * The panel side of the experiments tool. The page runs the toolbar's experiment logics and previews the variants, the
 * panel edits its own copy of the form.
 */
export const extensionExperimentsLogic = kea<extensionExperimentsLogicType>([
    path(['toolbar', 'extension', 'extensionExperimentsLogic']),
    connect(() => ({
        values: [extensionPageToolbarConnectionLogic, ['pageToolbarState']],
        actions: [extensionPageToolbarConnectionLogic, ['sendCommand']],
    })),
    actions({
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        sendExperimentsCommand: (command: PageExperimentsCommand) => ({ command }),
        selectExperiment: (id: number | 'new' | null) => ({ id }),
        renameVariant: (variant: string, newKey: string) => ({ variant, newKey }),
        setTransformField: (variant: string, index: number, field: 'html' | 'css', value: string) => ({
            variant,
            index,
            field,
            value,
        }),
        setSaveRequested: (saveRequested: boolean) => ({ saveRequested }),
    }),
    forms(({ actions }) => ({
        experimentForm: {
            defaults: EMPTY_EXPERIMENT_FORM,
            errors: ({ name }) => ({
                name: !name ? 'Please enter a name for this experiment' : undefined,
            }),
            submit: () => {
                actions.sendExperimentsCommand({ type: 'save-experiment' })
                capturePageToolUsed('save-experiment')
            },
            showErrorsOnTouch: true,
        },
    })),
    reducers({
        searchTerm: ['', { setSearchTerm: (_, { searchTerm }) => searchTerm }],
        // The page takes a moment to report that it started saving, so the button waits from the click.
        saveRequested: [
            false,
            {
                submitExperimentForm: () => true,
                // kea-forms fails the submit without calling submit when validation fails.
                submitExperimentFormFailure: () => false,
                setSaveRequested: (_, { saveRequested }) => saveRequested,
            },
        ],
    }),
    selectors({
        experimentsState: [
            (s) => [s.pageToolbarState],
            (pageToolbarState: PageToolbarState | null): PageToolbarExperimentsState | null =>
                pageToolbarState?.experiments ?? null,
        ],
        filteredExperiments: [
            (s) => [s.experimentsState, s.searchTerm],
            (
                experimentsState: PageToolbarExperimentsState | null,
                searchTerm: string
            ): PageToolbarExperimentsState['experiments'] =>
                (experimentsState?.experiments ?? []).filter(({ name }) =>
                    (name ?? '').toLowerCase().includes(searchTerm.trim().toLowerCase())
                ),
        ],
        saving: [
            (s) => [s.experimentsState, s.saveRequested],
            (experimentsState: PageToolbarExperimentsState | null, saveRequested: boolean): boolean =>
                saveRequested || !!experimentsState?.saving,
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        sendExperimentsCommand: ({ command }) => {
            // Every command can make the page change the form, so the page gets the user's edits first.
            if (command.type !== 'set-experiment-form') {
                cache.formSync.flush()
            }
            actions.sendCommand({ tool: 'experiments', command })
        },
        setExperimentFormValue: () => cache.formSync.schedule(),
        setExperimentFormValues: () => cache.formSync.schedule(),
        selectExperiment: ({ id }) => {
            actions.sendExperimentsCommand({ type: 'select-experiment', id })
            if (id === 'new') {
                capturePageToolUsed('create-experiment')
            }
        },
        setTransformField: ({ variant, index, field, value }) => {
            const webVariant = values.experimentForm.variants[variant]
            if (webVariant) {
                actions.setExperimentFormValue('variants', {
                    ...values.experimentForm.variants,
                    [variant]: {
                        ...webVariant,
                        transforms: webVariant.transforms.map((transform, i) =>
                            i === index ? { ...transform, [field]: value } : transform
                        ),
                    },
                })
            }
        },
        renameVariant: ({ variant, newKey }) => {
            const { variants } = values.experimentForm
            if (!canRenameVariant(variants, variant, newKey)) {
                return
            }
            actions.setExperimentFormValues({
                variants: Object.fromEntries(
                    Object.entries(variants).map(([key, value]) => [key === variant ? newKey : key, value])
                ),
            })
            actions.sendExperimentsCommand({ type: 'select-experiment-variant', variant: newKey })
        },
    })),
    afterMount(({ actions, values, cache }) => {
        cache.formSync = new PageFormSync(() =>
            actions.sendCommand({
                tool: 'experiments',
                command: { type: 'set-experiment-form', form: values.experimentForm },
            })
        )
        cache.disposables.add(() => () => cache.formSync.cancel(), 'formSync')
    }),
    // Runs after afterMount above, which creates the form sync the first call reads.
    subscriptions(({ actions, values, cache }) => ({
        experimentsState: (page: PageToolbarExperimentsState | null) => {
            if (!page) {
                return
            }
            if (cache.formSync.adopt(page.selectedExperimentId, page.formRevision)) {
                actions.setSaveRequested(false)
                actions.resetExperimentForm(page.experimentForm)
            } else if (values.saveRequested && !page.saving && page.saveResult) {
                actions.setSaveRequested(false)
            }
        },
    })),
])
