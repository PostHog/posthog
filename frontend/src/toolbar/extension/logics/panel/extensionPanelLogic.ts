export const extensionPanelLogic = kea<extensionPanelLogicType>([
    path(['toolbar', 'extension', 'extensionPanelLogic']),
    actions({
        setTab: (tabId: number | null, tabUrl: string | null) => ({ tabId, tabUrl }),
        setDataAttributes: (dataAttributes: string[]) => ({ dataAttributes }),
        setUiHost: (uiHost: string) => ({ uiHost }),
        setHostPermission: (granted: boolean) => ({ granted }),
        requestHostPermission: true,
        switchProject: (teamId: number) => ({ teamId }),
        openPostHogPath: (path: string) => ({ path }),
        openProjectPath: (path: string) => ({ path }),
        openFeature: (feature: ExtensionFeatureKey, path: string) => ({ feature, path }),
        retry: true,
        setProjectSwitchFailed: (failed: boolean) => ({ failed }),
        setSettingsExpanded: (expanded: boolean) => ({ expanded }),
    }),
    reducers({
        tabId: [null as number | null, { setTab: (_, { tabId }) => tabId }],
        tabUrl: [undefined as string | null | undefined, { setTab: (_, { tabUrl }) => tabUrl }],
        dataAttributes: [DEFAULT_DATA_ATTRIBUTES, { setDataAttributes: (_, { dataAttributes }) => dataAttributes }],
        uiHost: [DEFAULT_UI_HOST as string, { setUiHost: (_, { uiHost }) => uiHost }],
        projectSwitchFailed: [
            false,
            { setProjectSwitchFailed: (_, { failed }) => failed, switchProject: () => false, setUiHost: () => false },
        ],
        hostPermission: [
            null as boolean | null,
            { setUiHost: () => null, setHostPermission: (_, { granted }) => granted },
        ],
        settingsExpanded: [false, { setSettingsExpanded: (_, { expanded }) => expanded }],
    }),
    loaders(({ actions, values }) => ({
        sessionUser: [
            null as SessionUserResult | null,
            {
                loadSessionUser: async (): Promise<SessionUserResult | null> => {
                    const uiHost = values.uiHost
                    const { status, data } = await fetchWithSession(uiHost, getUsersRetrieveUrl('@me'))
                    if (values.uiHost !== uiHost) {
                        return null
                    }
                    if (status === 401 || status === 403) {
                        return { status: 'signed-out' }
                    }
                    const user = data as UserApi | null
                    if (status !== 200 || !user?.team) {
                        return { status: 'error' }
                    }
                    return { status: 'signed-in', user }
                },
            },
        ],
        toolbarAccess: [
            null as ToolbarAccessResult | null,
            {
                loadToolbarAccess: async (): Promise<ToolbarAccessResult | null> => {
                    const uiHost = values.uiHost
                    const { status, data } = await readResponse(fetchToolbarEntitlements(uiHost))
                    if (values.uiHost !== uiHost) {
                        return null
                    }
                    if (status === 200) {
                        const entitlements = (data as { entitlements?: ToolbarEntitlementsApiEntitlements } | null)
                            ?.entitlements
                        return { status: 'allowed', entitlements: entitlements ?? null }
                    }
                    if (status === 401) {
                        return { status: 'signed-out' }
                    }
                    return status === 403 ? { status: 'denied' } : { status: 'error' }
                },
            },
        ],
        authorizedUrls: [
            null as string[] | 'error' | null,
            {
                loadAuthorizedUrls: async ({
                    organizationId,
                    projectId,
                }: {
                    organizationId: string
                    projectId: number
                }): Promise<string[] | 'error' | null> => {
                    const uiHost = values.uiHost
                    const { status, data } = await fetchWithSession(
                        uiHost,
                        getOrganizationsProjectsRetrieveUrl(organizationId, projectId)
                    )
                    if (values.uiHost !== uiHost) {
                        return null
                    }
                    if (status !== 200 || !data) {
                        return 'error'
                    }
                    const project = data as ProjectBackwardCompatApi
                    if (Array.isArray(project.data_attributes)) {
                        actions.setDataAttributes(
                            project.data_attributes.filter(
                                (attribute): attribute is string => typeof attribute === 'string'
                            )
                        )
                    }
                    return (project.app_urls ?? []).filter(
                        (url): url is string => typeof url === 'string' && url.length > 0
                    )
                },
            },
        ],
    })),
    reducers({
        sessionUser: { setUiHost: () => null, switchProject: () => null, retry: () => null },
        toolbarAccess: { setUiHost: () => null, switchProject: () => null, retry: () => null },
        authorizedUrls: { setUiHost: () => null, switchProject: () => null, retry: () => null },
    }),
    selectors({
        user: [
            (s) => [s.sessionUser],
            (sessionUser: SessionUserResult | null): UserApi | null =>
                sessionUser?.status === 'signed-in' ? sessionUser.user : null,
        ],
        projectUrl: [
            (s) => [s.uiHost, s.user],
            (uiHost: string, user: UserApi | null) =>
                (path: string): string =>
                    joinWithUiHost(uiHost, user ? `/project/${user.team.id}${path}` : path),
        ],
        entitlements: [
            (s) => [s.toolbarAccess],
            (toolbarAccess: ToolbarAccessResult | null): ToolbarEntitlementsApiEntitlements | null =>
                toolbarAccess?.status === 'allowed' ? toolbarAccess.entitlements : null,
        ],
        panelState: [
            (s) => [s.tabUrl, s.uiHost, s.hostPermission, s.sessionUser, s.toolbarAccess, s.authorizedUrls],
            (
                tabUrl: string | null | undefined,
                uiHost: string,
                hostPermission: boolean | null,
                sessionUser: SessionUserResult | null,
                toolbarAccess: ToolbarAccessResult | null,
                authorizedUrls: string[] | 'error' | null
            ): ExtensionPanelState =>
                getExtensionPanelState({
                    tabUrl,
                    uiHost,
                    hostPermission,
                    sessionStatus: sessionUser?.status ?? null,
                    toolbarAccess,
                    authorizedUrls,
                }),
        ],
        settingsNeeded: [
            (s) => [s.panelState, s.projectSwitchFailed],
            (panelState: ExtensionPanelState, projectSwitchFailed: boolean): boolean =>
                projectSwitchFailed || OPEN_SETTINGS_IN.includes(panelState.kind),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setUiHost: async ({ uiHost }) => {
            void setStoredUiHost(uiHost)
            actions.setHostPermission(await hasHostPermission(uiHost))
        },
        requestHostPermission: async () => {
            // No await before this call: the prompt needs the click's user gesture.
            const granted = await requestHostPermission(values.uiHost)
            actions.setHostPermission(granted)
        },
        setHostPermission: ({ granted }) => {
            if (granted) {
                actions.loadSessionUser()
                actions.loadToolbarAccess()
            }
        },
        retry: () => {
            if (values.hostPermission) {
                actions.loadSessionUser()
                actions.loadToolbarAccess()
            }
        },
        setTab: () => {
            // The panel stays open while the user logs in, switches project or adds an authorized URL in another
            // tab, so check again when the user comes back.
            if (RECHECK_ON_TAB_CHANGE.includes(values.panelState.kind)) {
                actions.retry()
                return
            }
            if (values.hostPermission && Date.now() - (cache.lastRefresh ?? 0) > REFRESH_ON_TAB_CHANGE_MS) {
                cache.lastRefresh = Date.now()
                actions.loadSessionUser()
                actions.loadToolbarAccess()
                toolbarPosthogJS.reloadFeatureFlags()
            }
        },
        loadSessionUserSuccess: ({ sessionUser }) => {
            if (sessionUser?.status !== 'signed-in') {
                return
            }
            const { user } = sessionUser
            if (user.distinct_id) {
                // Evaluates toolbar rollout flags for this person, as the floating toolbar does.
                toolbarPosthogJS.identify(user.distinct_id)
            }
            actions.loadAuthorizedUrls({ organizationId: user.organization.id, projectId: user.team.project_id })
        },
        switchProject: async ({ teamId }) => {
            // The app's project-switch path moves the session's current project, which is the project
            // toolbar authentication uses.
            const { status } = await fetchWithSession(values.uiHost, `/project/${teamId}`)
            if (status >= 200 && status < 300) {
                toolbarPosthogJS.capture('toolbar extension project switched')
            } else {
                actions.setProjectSwitchFailed(true)
            }
            actions.loadSessionUser()
            actions.loadToolbarAccess()
        },
        openPostHogPath: ({ path }) => {
            void openTab(joinWithUiHost(values.uiHost, path))
        },
        openProjectPath: ({ path }) => {
            void openTab(values.projectUrl(path))
        },
        openFeature: ({ feature, path }) => {
            toolbarPosthogJS.capture('toolbar extension feature opened', { feature })
            actions.openProjectPath(path)
        },
    })),
    subscriptions(({ actions }) => ({
        settingsNeeded: (settingsNeeded: boolean, previous: boolean | undefined) => {
            // Opens the settings when a problem starts and closes them when it ends, so the user can still toggle
            // them in between.
            if (settingsNeeded || previous) {
                actions.setSettingsExpanded(settingsNeeded)
            }
        },
        panelState: (panelState: ExtensionPanelState, previous: ExtensionPanelState | undefined) => {
            if (panelState.kind === 'checking' || panelState.kind === previous?.kind) {
                return
            }
            // pinned: analytics event name, renaming it breaks the extension adoption insights
            toolbarPosthogJS.capture('toolbar extension panel state', {
                state: panelState.kind,
                unsupported_reason: panelState.kind === 'unsupported-page' ? panelState.reason : undefined,
            })
        },
    })),
    afterMount(({ actions, cache }) => {
        // Setup runs again when the panel shows after it was hidden, so it reads the choice again then too.
        cache.disposables.add(() => {
            void syncUsageDataConsent()
            return onPermissionsChange(() => void syncUsageDataConsent())
        }, 'usageDataConsent')
        void getStoredUiHost().then((stored) => actions.setUiHost(canonicalizeUiHost(stored) ?? DEFAULT_UI_HOST))
        void getActiveTab().then(
            (tab) => actions.setTab(tab?.id ?? null, tab?.url ?? null),
            () => actions.setTab(null, null)
        )
        cache.removeActiveTabListener = onActiveTabChange((tab) => actions.setTab(tab?.id ?? null, tab?.url ?? null))
    }),
    beforeUnmount(({ cache }) => {
        cache.removeActiveTabListener?.()
    }),
])
