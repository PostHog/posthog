const DEFAULT_UI_HOST = 'https://us.posthog.com'

// The project setting's default, used until the project loads.
const DEFAULT_DATA_ATTRIBUTES = ['data-attr']

// Matches the toolbar's entitlements request timeout.
const REQUEST_TIMEOUT_MS = 5000

const REFRESH_ON_TAB_CHANGE_MS = 30 * 1000

const RECHECK_ON_TAB_CHANGE: ExtensionPanelState['kind'][] = [
    'signed-out',
    'no-toolbar-access',
    'unauthorized-url',
    'error',
]

// States the user may fix with the project or host settings, for example a session on the other cloud region.
const OPEN_SETTINGS_IN: ExtensionPanelState['kind'][] = [
    'host-permission-needed',
    'signed-out',
    'no-toolbar-access',
    'error',
]

async function syncUsageDataConsent(): Promise<void> {
    // posthog-js keeps an earlier opt-in in localStorage, so a revoked choice needs an explicit opt-out.
    if (await canSendUsageData()) {
        toolbarPosthogJS.opt_in_capturing()
    } else {
        toolbarPosthogJS.opt_out_capturing()
    }
}

/** Sends the PostHog session cookie, like the toolbar's own entitlements request. */
async function fetchWithSession(uiHost: string, path: string): Promise<{ status: number; data: unknown }> {
    return await readResponse(
        safeFetch(`${uiHost}${path}`, { credentials: 'include', signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS) })
    )
}

async function readResponse(request: Promise<Response>): Promise<{ status: number; data: unknown }> {
    try {
        const response = await request
        const data = response.ok ? await response.json() : null
        return { status: response.status, data }
    } catch {
        // 0 keeps a network failure apart from every HTTP status.
        return { status: 0, data: null }
    }
}

