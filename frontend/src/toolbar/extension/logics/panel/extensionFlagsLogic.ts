/** The panel side of the flags tool. The page runs the toolbar's flags logic, which applies the overrides. */
export const extensionFlagsLogic = kea<extensionFlagsLogicType>([
    path(['toolbar', 'extension', 'extensionFlagsLogic']),
    connect(() => ({
        values: [extensionPageToolbarConnectionLogic, ['pageToolbarState', 'flagComparison']],
        actions: [
            extensionPageToolbarConnectionLogic,
            ['sendCommand', 'receiveState', 'receivePatch', 'receiveFlagComparison'],
        ],
    })),
    actions({
        setSearchTerm: (searchTerm: string) => ({ searchTerm }),
        sendFlagsMutation: (command: PageFlagsCommand, revision: number) => ({ command, revision }),
        setFlagOverride: (flagKey: string, value: FlagValue) => ({ flagKey, value }),
        removeFlagOverride: (flagKey: string) => ({ flagKey }),
        clearOverrides: true,
        reloadFlags: true,
        openPayloadEditor: (flagKey: string, draftPayload: string) => ({ flagKey, draftPayload }),
        closePayloadEditor: (flagKey: string) => ({ flagKey }),
        setDraftPayload: (flagKey: string, draftPayload: string) => ({ flagKey, draftPayload }),
        savePayload: (flagKey: string) => ({ flagKey }),
        setImpersonationOpen: (open: boolean) => ({ open }),
        setDraftDistinctId: (draftDistinctId: string) => ({ draftDistinctId }),
        impersonate: (distinctId: string) => ({ distinctId }),
        clearImpersonation: true,
        compareFlag: (flag: FlagInfo) => ({ flag }),
        closeComparison: true,
        setAfterValue: (value: string | boolean) => ({ value }),
    }),
    reducers({
        searchTerm: ['', { setSearchTerm: (_, { searchTerm }) => searchTerm }],
        draftPayloads: [
            {} as Record<string, string>,
            {
                openPayloadEditor: (state, { flagKey, draftPayload }) => ({ ...state, [flagKey]: draftPayload }),
                setDraftPayload: (state, { flagKey, draftPayload }) => ({ ...state, [flagKey]: draftPayload }),
                closePayloadEditor: (state, { flagKey }) => {
                    const { [flagKey]: _, ...rest } = state
                    return rest
                },
            },
        ],
        impersonationOpen: [false, { setImpersonationOpen: (_, { open }) => open, clearImpersonation: () => false }],
        draftDistinctId: [
            '',
            { setDraftDistinctId: (_, { draftDistinctId }) => draftDistinctId, impersonate: () => '' },
        ],
        // The page's revision when the panel sent a change. It blocks a second change until the page answers the
        // first, so two overrides can't race in the page. The page times out a change it can't apply.
        sentAtRevision: [
            null as number | null,
            {
                sendFlagsMutation: (_, { revision }) => revision,
                receiveState: () => null,
                receivePatch: (sent, { patch }) =>
                    sent !== null && patch.flags && patch.flags.mutationRevision > sent ? null : sent,
            },
        ],
        // The page checks the JSON, so the editor stays open until the page accepts the payload.
        savingPayloadKey: [
            null as string | null,
            { savePayload: (_, { flagKey }) => flagKey, closePayloadEditor: () => null, receiveState: () => null },
        ],
        afterValue: [
            null as string | boolean | null,
            { compareFlag: () => null, setAfterValue: (_, { value }) => value },
        ],
    }),
    selectors({
        flagsState: [
            (s) => [s.pageToolbarState],
            (pageToolbarState: PageToolbarState | null): PageToolbarFlagsState | null =>
                pageToolbarState?.flags ?? null,
        ],
        filteredFlags: [
            (s) => [s.flagsState, s.searchTerm],
            (flagsState: PageToolbarFlagsState | null, searchTerm: string): FlagInfo[] =>
                (flagsState?.flags ?? []).filter(({ key }) =>
                    key.toLowerCase().includes(searchTerm.trim().toLowerCase())
                ),
        ],
        mutationDisabledReason: [
            (s) => [s.flagsState, s.sentAtRevision],
            (flagsState: PageToolbarFlagsState | null, sentAtRevision: number | null): string | null =>
                !flagsState?.available
                    ? 'This page has no posthog-js to override'
                    : flagsState.comparingFlagKey
                      ? 'Wait for the comparison to finish'
                      : sentAtRevision !== null || flagsState.mutationPending
                        ? 'Applying the last change…'
                        : null,
        ],
        comparingFlagKey: [
            (s) => [s.flagsState],
            (flagsState: PageToolbarFlagsState | null): string | null => flagsState?.comparingFlagKey ?? null,
        ],
        comparisonError: [
            (s) => [s.flagsState],
            (flagsState: PageToolbarFlagsState | null): FlagComparisonFailureReason | null =>
                flagsState?.comparisonError ?? null,
        ],
        beforeCapture: [
            (s) => [s.flagComparison],
            (flagComparison: FlagComparison | null): FlagComparisonCapture | null =>
                flagComparison?.captures[0] ?? null,
        ],
        onCaptures: [
            (s) => [s.flagComparison],
            (flagComparison: FlagComparison | null): FlagComparisonCapture[] => flagComparison?.captures.slice(1) ?? [],
        ],
        afterCapture: [
            (s) => [s.onCaptures, s.afterValue],
            (onCaptures: FlagComparisonCapture[], afterValue: string | boolean | null): FlagComparisonCapture | null =>
                pickAfterCapture(onCaptures, afterValue),
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const sendMutation = (command: PageFlagsCommand): void =>
            actions.sendFlagsMutation(command, values.flagsState?.mutationRevision ?? 0)
        return {
            sendFlagsMutation: ({ command }) => {
                actions.sendCommand({ tool: 'flags', command })
            },
            setFlagOverride: ({ flagKey, value }) => {
                if (!values.mutationDisabledReason) {
                    sendMutation({ type: 'set-flag-override', flagKey, value })
                    capturePageToolUsed('override-flag')
                }
            },
            removeFlagOverride: ({ flagKey }) => {
                if (!values.mutationDisabledReason) {
                    sendMutation({ type: 'remove-flag-override', flagKey })
                }
            },
            clearOverrides: () => {
                if (!values.mutationDisabledReason) {
                    sendMutation({ type: 'clear-flag-overrides' })
                    capturePageToolUsed('clear-flag-overrides')
                }
            },
            reloadFlags: () => {
                actions.sendCommand({ tool: 'flags', command: { type: 'reload-flags' } })
            },
            savePayload: ({ flagKey }) => {
                if (values.mutationDisabledReason) {
                    return
                }
                sendMutation({ type: 'save-flag-payload', flagKey, draftPayload: values.draftPayloads[flagKey] ?? '' })
                capturePageToolUsed('override-flag', { payload: true })
            },
            receivePatch: ({ patch }) => {
                const flagKey = values.savingPayloadKey
                if (flagKey && patch.flags && values.sentAtRevision === null && !patch.flags.payloadErrors[flagKey]) {
                    actions.closePayloadEditor(flagKey)
                }
                if (cache.comparisonStartedAt !== undefined && patch.flags?.comparisonError) {
                    captureFlagComparison('failed', { reason: patch.flags.comparisonError })
                    cache.comparisonStartedAt = undefined
                }
            },
            compareFlag: ({ flag }) => {
                if (values.mutationDisabledReason) {
                    return
                }
                actions.sendCommand({ tool: 'flags', command: { type: 'compare-flag', flagKey: flag.key } })
                capturePageToolUsed('compare-flag')
                // Only the panel that started the comparison reports how it ended.
                cache.comparisonStartedAt = performance.now()
                captureFlagComparison('started', { state_count: comparisonStates(flag).length })
            },
            closeComparison: () => {
                actions.sendCommand({ tool: 'flags', command: { type: 'close-flag-comparison' } })
            },
            receiveFlagComparison: ({ comparison }) => {
                if (comparison && cache.comparisonStartedAt !== undefined) {
                    captureFlagComparison('completed', {
                        state_count: comparison.captures.length,
                        identical: comparison.identical,
                        duration_ms: Math.round(performance.now() - cache.comparisonStartedAt),
                    })
                    cache.comparisonStartedAt = undefined
                }
            },
            impersonate: ({ distinctId }) => {
                if (values.comparingFlagKey) {
                    return
                }
                // The page loads the person's flags from PostHog before it overrides anything, so this doesn't wait.
                actions.sendCommand({ tool: 'flags', command: { type: 'impersonate-flags', distinctId } })
                capturePageToolUsed('impersonate-flags')
            },
            clearImpersonation: () => {
                if (!values.mutationDisabledReason) {
                    sendMutation({ type: 'clear-flag-impersonation' })
                }
            },
        }
    }),
])
