export const flagComparisonLogic = kea<flagComparisonLogicType>([
    path(['toolbar', 'flags', 'flagComparisonLogic']),
    connect(() => ({
        values: [toolbarConfigLogic, ['posthog', 'ownsPageSession']],
        actions: [flagsToolbarLogic, ['checkLocalOverrides'], toolbarLogic, ['setVisibleMenu']],
    })),
    actions({
        compareFlag: (flag: FlagInfo) => ({ flag }),
        closeComparison: true,
        setAfterValue: (value: string | boolean) => ({ value }),
    }),
    loaders(({ values, actions, cache }) => ({
        comparison: [
            null as FlagComparison | null,
            {
                compareFlag: async ({ flag }): Promise<FlagComparison> => {
                    const posthog = values.posthog
                    if (!posthog) {
                        throw new Error('The page has no PostHog client to override flags with')
                    }
                    // Checked before any override is written, so a refused run leaves the page as it is.
                    if (isCaptureRunning()) {
                        throw new CaptureStillRunningError()
                    }
                    revokeComparison(values.comparison)

                    const states = comparisonStates(flag)
                    const startedAt = performance.now()
                    toolbarPosthogJS.capture('toolbar feature flag comparison started', {
                        state_count: states.length,
                    })

                    const previousOverrides = readFlagOverrides(posthog)
                    // Logout, an expired token or an impersonation load can replace the overrides during the run.
                    // Their state then wins, so the comparison stops and does not restore over it.
                    let lastWritten = previousOverrides
                    const ownsOverrides = (): boolean => objectsEqual(readFlagOverrides(posthog), lastWritten)
                    const restoreOverrides = (): void => {
                        if (ownsOverrides()) {
                            writeFlagOverrides(posthog, previousOverrides)
                        }
                    }
                    // The SDK persists overrides, and a reload or a link click during the run skips the `finally` below.
                    cache.disposables.add(
                        () => {
                            window.addEventListener('pagehide', restoreOverrides)
                            return () => window.removeEventListener('pagehide', restoreOverrides)
                        },
                        'restoreOverridesOnPageHide',
                        { pauseOnPageHidden: false }
                    )
                    const captures: FlagComparisonCapture[] = []
                    let offBlob: Blob | null = null
                    try {
                        for (const state of states) {
                            if (!ownsOverrides()) {
                                throw new FlagOverridesChangedError()
                            }
                            lastWritten = { ...previousOverrides, [flag.key]: state.value }
                            writeFlagOverrides(posthog, lastWritten)
                            await waitForPageToSettle()
                            const { blob, width, height } = await capturePage()
                            if (!ownsOverrides()) {
                                throw new FlagOverridesChangedError()
                            }
                            offBlob ??= blob
                            captures.push({
                                ...state,
                                url: URL.createObjectURL(blob),
                                width,
                                height,
                                sameAsOff: await imagesMatch(offBlob, blob),
                            })
                        }
                    } catch (error) {
                        captures.forEach((capture) => URL.revokeObjectURL(capture.url))
                        throw error
                    } finally {
                        cache.disposables.dispose('restoreOverridesOnPageHide')
                        restoreOverrides()
                        actions.checkLocalOverrides()
                    }

                    const identical = captures.every((capture) => capture.sameAsOff)
                    toolbarPosthogJS.capture('toolbar feature flag comparison completed', {
                        state_count: states.length,
                        identical,
                        duration_ms: Math.round(performance.now() - startedAt),
                    })
                    return { flagKey: flag.key, captures, identical }
                },
                closeComparison: () => {
                    revokeComparison(values.comparison)
                    return null
                },
            },
        ],
    })),
    reducers({
        comparingFlagKey: [
            null as string | null,
            {
                compareFlag: (_, { flag }) => flag.key,
                compareFlagSuccess: () => null,
                compareFlagFailure: () => null,
            },
        ],
        afterValue: [
            null as string | boolean | null,
            {
                compareFlag: () => null,
                setAfterValue: (_, { value }) => value,
            },
        ],
    }),
    selectors({
        beforeCapture: [
            (s) => [s.comparison],
            (comparison: FlagComparison | null): FlagComparisonCapture | null => comparison?.captures[0] ?? null,
        ],
        onCaptures: [
            (s) => [s.comparison],
            (comparison: FlagComparison | null): FlagComparisonCapture[] => comparison?.captures.slice(1) ?? [],
        ],
        afterCapture: [
            (s) => [s.onCaptures, s.afterValue],
            (onCaptures: FlagComparisonCapture[], afterValue: string | boolean | null): FlagComparisonCapture | null =>
                pickAfterCapture(onCaptures, afterValue),
        ],
    }),
    listeners(({ actions, values }) => ({
        compareFlagSuccess: () => {
            // The modal renders inside the flags menu, which the user may have closed during the capture. The extension
            // shows the comparison in its panel instead, and opening a menu in its content script would turn off the
            // heatmap or Inspect that the panel shows.
            if (values.ownsPageSession) {
                actions.setVisibleMenu('flags')
            }
        },
        compareFlagFailure: ({ errorObject }) => {
            toolbarPosthogJS.capture('toolbar feature flag comparison failed', {
                reason: comparisonFailureReason(errorObject),
            })
            if (errorObject instanceof FlagOverridesChangedError) {
                lemonToast.info('The comparison stopped because the flag overrides changed. Start it again to compare.')
                return
            }
            if (errorObject instanceof CaptureStillRunningError) {
                lemonToast.info('The last capture is still finishing. Try again in a few seconds.')
                return
            }
            lemonToast.error(
                "Couldn't capture the page. Images or fonts from other sites can block the capture. Try again on a page without them."
            )
        },
    })),
    beforeUnmount(({ values }) => {
        revokeComparison(values.comparison)
    }),
    // A comparison writes overrides to the page for several seconds.
    // The logic stays mounted when the flags menu closes, so the `pagehide` restore stays attached
    // and `comparingFlagKey` keeps the override controls disabled until the comparison ends.
    permanentlyMount(),
])
