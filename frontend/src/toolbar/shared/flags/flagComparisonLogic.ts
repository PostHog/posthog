export interface FlagComparisonCapture {
    value: string | boolean
    label: string
    /** An object URL, which the logic revokes when the comparison closes. The extension sends its panel a data URL instead. */
    url: string
    width: number
    height: number
    /** The page looked the same as with the flag off. Always true for the off capture itself. */
    sameAsOff: boolean
}

export interface FlagComparison {
    flagKey: string
    /** The first capture is the flag turned off. */
    captures: FlagComparisonCapture[]
    identical: boolean
}

// pinned: `reason` values of the comparison failed event, which the extension also shows in its panel. Error messages
// can quote page content, so they are never sent.
export type FlagComparisonFailureReason =
    | 'overrides_changed'
    | 'capture_still_running'
    | 'capture_timeout'
    | 'capture_failed'
    | 'captures_too_large'

export function comparisonFailureReason(error: unknown): FlagComparisonFailureReason {
    if (error instanceof FlagOverridesChangedError) {
        return 'overrides_changed'
    }
    if (error instanceof CaptureStillRunningError) {
        return 'capture_still_running'
    }
    if (error instanceof PromiseTimeoutError) {
        return 'capture_timeout'
    }
    return 'capture_failed'
}

function revokeComparison(comparison: FlagComparison | null): void {
    comparison?.captures.forEach((capture) => URL.revokeObjectURL(capture.url))
}

