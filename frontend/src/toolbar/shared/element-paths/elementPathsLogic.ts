type ElementPathsOutcome = { kind: 'result'; result: ElementPathsResult } | { kind: 'unavailable' } | { kind: 'error' }

interface ElementPathsResponse {
    /** The query the outcome answers. Until the answer for the current query arrives, the view shows loading. */
    queryKey: string
    rangeLabel: string
    outcome: ElementPathsOutcome
}

