/**
 * The most common paths through the selected element, for the element card. Mount it only while the card shows the
 * section, because each selection runs a query. The hovered element never loads paths.
 */
export const elementPathsLogic = kea<elementPathsLogicType>([
    path(['toolbar', 'element-paths', 'elementPathsLogic']),
    connect(() => ({
        values: [elementsLogic, ['selectedElementMeta'], heatmapDataLogic, ['commonFilters']],
        actions: [
            elementsLogic,
            ['setSelectedElement'],
            heatmapDataLogic,
            ['setCommonFilters'],
            currentPageLogic,
            ['setHref'],
        ],
    })),
    actions({
        refreshElementPaths: true,
        retryElementPaths: true,
        reportSaveClicked: (pathIndex: number) => ({ pathIndex }),
    }),
    loaders(({ values }) => ({
        elementPathsResponse: [
            null as ElementPathsResponse | null,
            {
                loadElementPaths: async (query: ElementPathsParams, breakpoint) => {
                    const queryKey = JSON.stringify(query)
                    const rangeLabel = elementPathsDateRange(values.commonFilters).label
                    const result = await toolbarApi.elementPaths.get(query, { context: 'load_element_paths' })
                    // A newer request replaces this one, so a late answer can't overwrite the newer answer.
                    breakpoint()
                    if (result.ok) {
                        return { queryKey, rangeLabel, outcome: { kind: 'result', result: result.data } }
                    }
                    // A 404 means the project doesn't have user journeys, which is not an error to show.
                    return { queryKey, rangeLabel, outcome: { kind: result.status === 404 ? 'unavailable' : 'error' } }
                },
            },
        ],
    })),
    selectors({
        elementPathsQuery: [
            (s) => [s.selectedElementMeta, s.commonFilters],
            (
                selectedElementMeta: ElementWithMetadata | null,
                commonFilters: CommonFilters
            ): ElementPathsParams | null => elementPathsQuery(selectedElementMeta?.actionStep, commonFilters),
        ],
        elementPathsQueryKey: [
            (s) => [s.elementPathsQuery],
            (elementPathsQuery: ElementPathsParams | null): string | null =>
                elementPathsQuery ? JSON.stringify(elementPathsQuery) : null,
        ],
        elementPathsView: [
            (s) => [s.elementPathsQueryKey, s.elementPathsResponse, s.elementPathsResponseLoading],
            (
                elementPathsQueryKey: string | null,
                elementPathsResponse: ElementPathsResponse | null,
                elementPathsResponseLoading: boolean
            ): ElementPathsView => {
                if (!elementPathsQueryKey) {
                    return { status: 'idle' }
                }
                if (elementPathsResponseLoading || elementPathsResponse?.queryKey !== elementPathsQueryKey) {
                    return { status: 'loading' }
                }
                const { outcome, rangeLabel } = elementPathsResponse
                if (outcome.kind !== 'result') {
                    return { status: outcome.kind }
                }
                return { status: resolvedElementPathsStatus(outcome.result), result: outcome.result, rangeLabel }
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        refreshElementPaths: () => {
            const { elementPathsQuery: query, elementPathsQueryKey: queryKey } = values
            // The selection, the heatmap filters and the URL change together, so most refreshes ask the same question.
            if (query && queryKey !== cache.requestedQueryKey) {
                cache.requestedQueryKey = queryKey
                actions.loadElementPaths(query)
            }
        },
        retryElementPaths: () => {
            cache.requestedQueryKey = null
            actions.refreshElementPaths()
        },
        loadElementPathsSuccess: () => {
            captureElementPathsViewed(values.elementPathsView)
        },
        setSelectedElement: () => actions.refreshElementPaths(),
        setCommonFilters: () => actions.refreshElementPaths(),
        setHref: () => actions.refreshElementPaths(),
        reportSaveClicked: ({ pathIndex }) => {
            captureElementPathsSaveClicked(values.elementPathsView, pathIndex)
        },
    })),
    afterMount(({ actions }) => {
        actions.refreshElementPaths()
    }),
])
