import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from 'lib/lemon-ui/LemonToast'

import { heatmapToolbarMenuLogic } from '~/toolbar/elements/heatmapToolbarMenuLogic'
import { currentPageLogic } from '~/toolbar/stats/currentPageLogic'
import { toolbarApi } from '~/toolbar/toolbarApi'
import { toolbarConfigLogic } from '~/toolbar/toolbarConfigLogic'
import { ToolbarRequestError } from '~/toolbar/toolbarRequestError'
import { urls } from '~/toolbar/urls'
import { joinWithUiHost } from '~/toolbar/utils'
import {
    RESPONSIVE_CAPTURE_WIDTHS,
    WidthCapture,
    captureResponsiveScreenshots,
} from '~/toolbar/utils/responsiveScreenshot'
import { captureElementScreenshot } from '~/toolbar/utils/screenshot'

interface HeatmapCaptureResult {
    id: string
    short_id: string
}

interface CaptureProgress {
    done: number
    total: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface heatmapCaptureLogicValues {
    href: string // currentPageLogic
    windowWidth: number // heatmapToolbarMenuLogic
    isAuthenticated: boolean // toolbarConfigLogic
    uiHost: string // toolbarConfigLogic
    captureProgress: CaptureProgress | null
    captureResult: HeatmapCaptureResult | null
    captureResultLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface heatmapCaptureLogicActions {
    saveToPostHog: () => any
    saveToPostHogFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    saveToPostHogSuccess: (
        captureResult: {
            id: string
            short_id: string
        },
        payload?: any
    ) => {
        captureResult: {
            id: string
            short_id: string
        }
        payload?: any
    }
    setCaptureProgress: (progress: CaptureProgress | null) => {
        progress: CaptureProgress | null
    }
}

export type heatmapCaptureLogicType = MakeLogicType<heatmapCaptureLogicValues, heatmapCaptureLogicActions>

function buildBaseFormData(href: string): FormData {
    const formData = new FormData()
    formData.append('url', href)
    formData.append('name', document.title || href)
    return formData
}

function buildMultiWidthFormData(href: string, captures: WidthCapture[]): FormData {
    const formData = buildBaseFormData(href)
    for (const { width, blob } of captures) {
        formData.append('images', new File([blob], `heatmap-${width}.jpg`, { type: 'image/jpeg' }))
        formData.append('widths', String(width))
    }
    return formData
}

async function buildSingleWidthFormData(href: string, width: number): Promise<FormData> {
    const blob = await captureElementScreenshot(document.documentElement)
    const formData = buildBaseFormData(href)
    formData.append('image', new File([blob], `heatmap-${Date.now()}.jpg`, { type: 'image/jpeg' }))
    formData.append('width', String(width))
    return formData
}

export const heatmapCaptureLogic = kea<heatmapCaptureLogicType>([
    path(['toolbar', 'stats', 'heatmapCaptureLogic']),
    connect(() => ({
        values: [
            currentPageLogic,
            ['href'],
            heatmapToolbarMenuLogic,
            ['windowWidth'],
            toolbarConfigLogic,
            ['uiHost', 'isAuthenticated'],
        ],
    })),
    actions({
        setCaptureProgress: (progress: CaptureProgress | null) => ({ progress }),
    }),
    reducers({
        captureProgress: [
            null as CaptureProgress | null,
            {
                setCaptureProgress: (_, { progress }) => progress,
            },
        ],
    }),
    loaders(({ values, actions }) => ({
        captureResult: [
            null as HeatmapCaptureResult | null,
            {
                saveToPostHog: async () => {
                    actions.setCaptureProgress({ done: 0, total: RESPONSIVE_CAPTURE_WIDTHS.length })

                    const captures = await captureResponsiveScreenshots(RESPONSIVE_CAPTURE_WIDTHS, (done, total) =>
                        actions.setCaptureProgress({ done, total })
                    )
                    const formData =
                        captures.length > 0
                            ? buildMultiWidthFormData(values.href, captures)
                            : await buildSingleWidthFormData(values.href, values.windowWidth)

                    const result = await toolbarApi.savedHeatmaps.capture(formData, {
                        context: 'capture_heatmap',
                        reauthenticateOnForbidden: true,
                    })
                    if (!result.ok) {
                        throw new ToolbarRequestError(result.error.detail, result.status)
                    }
                    return result.data
                },
            },
        ],
    })),
    listeners(({ values, actions }) => ({
        saveToPostHogSuccess: ({ captureResult }) => {
            actions.setCaptureProgress(null)
            if (!captureResult) {
                return
            }
            lemonToast.success('Heatmap saved', {
                button: {
                    label: 'Open in PostHog',
                    action: () =>
                        window.open(joinWithUiHost(values.uiHost, urls.heatmap(captureResult.short_id)), '_blank'),
                },
            })
        },
        saveToPostHogFailure: ({ error }) => {
            actions.setCaptureProgress(null)
            lemonToast.error(`Couldn't save this heatmap: ${error}`)
        },
    })),
])
