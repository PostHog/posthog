export const eventDebugMenuLogic = kea<eventDebugMenuLogicType>([
    path(['toolbar', 'debug', 'eventDebugMenuLogic']),
    connect(() => ({
        values: [toolbarConfigLogic, ['posthog']],
    })),
    actions({
        refreshRegexSearch: true,
        resetRegexSearch: true,
        setSearchPending: (pending: boolean) => ({ pending }),
        setSearchResult: (events: EventType[], error: RegexMatchingError | null, literal: boolean) => ({
            events,
            error,
            literal,
        }),
        addEvent: (event: EventType) => ({ event }),
        markExpanded: (id: string | null | undefined) => ({ id }),
        setSearchText: (searchText: string) => ({ searchText }),
        setSelectedEventType: (eventType: EventCategory, enabled: boolean) => ({
            eventType,
            enabled,
        }),
        setHidePostHogProperties: (hide: boolean) => ({ hide }),
        setHidePostHogFlags: (hide: boolean) => ({ hide }),
        togglePinnedEvent: (eventId: string) => ({ eventId }),
        toggleRelativeTimestamps: true,
        togglePaused: true,
        clearEvents: true,
        exportEvents: true,
    }),
    reducers({
        regexMatchedEvents: [
            [] as EventType[],
            {
                resetRegexSearch: () => [],
                clearEvents: () => [],
                setSearchResult: (_, { events }) => events,
            },
        ],
        searchPending: [
            false,
            {
                resetRegexSearch: () => false,
                clearEvents: () => false,
                setSearchPending: (_, { pending }) => pending,
                setSearchResult: () => false,
            },
        ],
        searchError: [
            null as RegexMatchingError | null,
            {
                resetRegexSearch: () => null,
                setSearchResult: (_, { error }) => error,
            },
        ],
        literalSearch: [
            false,
            {
                resetRegexSearch: () => false,
                setSearchResult: (_, { literal }) => literal,
            },
        ],
        hidePostHogProperties: [
            false,
            {
                setHidePostHogProperties: (_, { hide }) => hide,
            },
        ],
        hidePostHogFlags: [
            false,
            {
                setHidePostHogFlags: (_, { hide }) => hide,
            },
        ],
        relativeTimestamps: [
            false,
            {
                toggleRelativeTimestamps: (state) => !state,
            },
        ],
        searchText: [
            '',
            {
                setSearchText: (_, { searchText }) => searchText,
            },
        ],
        selectedEventTypes: [
            ['posthog', 'custom'] as EventCategory[],
            {
                setSelectedEventType: (state, { eventType, enabled }) => {
                    if (enabled) {
                        return state.includes(eventType) ? state : [...state, eventType]
                    }
                    return state.filter((t) => t !== eventType)
                },
            },
        ],

        events: [
            [] as EventType[],
            {
                addEvent: (state, { event }) => {
                    const next = [{ ...event, uuid: event.uuid || uuid() }, ...state]
                    return next.length > MAX_EVENTS ? next.slice(0, MAX_EVENTS) : next
                },
                clearEvents: () => [],
            },
        ],
        // Events buffered while paused, prepended on resume
        bufferedEvents: [
            [] as EventType[],
            {
                addEvent: (state, { event }) => {
                    const next = [{ ...event, uuid: event.uuid || uuid() }, ...state]
                    return next.length > MAX_EVENTS ? next.slice(0, MAX_EVENTS) : next
                },
                togglePaused: () => [],
                clearEvents: () => [],
            },
        ],
        isPaused: [
            false,
            {
                togglePaused: (state) => !state,
            },
        ],
        expandedEvent: [
            null as string | null | undefined,
            {
                markExpanded: (_, { id }) => id,
            },
        ],
        pinnedEventIds: [
            new Set<string>(),
            {
                togglePinnedEvent: (state, { eventId }) => {
                    const next = new Set(state)
                    if (next.has(eventId)) {
                        next.delete(eventId)
                    } else {
                        next.add(eventId)
                    }
                    return next
                },
                clearEvents: () => new Set<string>(),
            },
        ],
    }),
    selectors({
        isCollapsedEventRow: [
            (s) => [s.expandedEvent],
            (expandedEvent: string | null | undefined) => {
                return (eventId: string | null | undefined): boolean => {
                    return eventId !== expandedEvent
                }
            },
        ],
        // When paused, show a frozen snapshot; when live, show all events
        visibleEvents: [
            (s) => [s.events, s.bufferedEvents, s.isPaused],
            (events: EventType[], bufferedEvents: EventType[], isPaused: boolean): EventType[] => {
                if (isPaused) {
                    // Show events minus anything buffered since pause
                    return events.slice(bufferedEvents.length)
                }
                return events
            },
        ],
        searchFilteredEvents: [
            (s) => [s.visibleEvents, s.searchText, s.regexMatchedEvents, s.literalSearch],
            (
                visibleEvents: EventType[],
                searchText: string,
                regexMatchedEvents: EventType[],
                literalSearch: boolean
            ): EventType[] => {
                if (!literalSearch && regexSearch(searchText)) {
                    const matches = new Set(regexMatchedEvents)
                    return visibleEvents.filter((event) => matches.has(event))
                }
                return visibleEvents.filter((event) => event.event.toLowerCase().includes(searchText.toLowerCase()))
            },
        ],
        searchFilteredEventsCount: [
            (s) => [s.searchFilteredEvents],
            (searchFilteredEvents: EventType[]): Record<EventCategory, number> => {
                const counts: Record<EventCategory, number> = { posthog: 0, custom: 0, snapshot: 0 }
                searchFilteredEvents.forEach((e: EventType) => {
                    counts[classifyEvent(e)] += 1
                })
                return counts
            },
        ],

        activeFilteredEvents: [
            (s) => [s.selectedEventTypes, s.searchFilteredEvents],
            (selectedEventTypes: EventCategory[], searchFilteredEvents: EventType[]) => {
                return searchFilteredEvents.filter((e: EventType) => {
                    return selectedEventTypes.includes(classifyEvent(e))
                })
            },
        ],

        totalEventsCount: [(s) => [s.visibleEvents], (visibleEvents: EventType[]): number => visibleEvents.length],

        bufferedCount: [(s) => [s.bufferedEvents], (bufferedEvents: EventType[]): number => bufferedEvents.length],

        pinnedEvents: [
            (s) => [s.activeFilteredEvents, s.pinnedEventIds],
            (activeFilteredEvents: EventType[], pinnedEventIds: Set<string>): EventType[] => {
                if (pinnedEventIds.size === 0) {
                    return []
                }
                return activeFilteredEvents.filter((e: EventType) => e.uuid && pinnedEventIds.has(e.uuid))
            },
        ],

        unpinnedEvents: [
            (s) => [s.activeFilteredEvents, s.pinnedEventIds],
            (activeFilteredEvents: EventType[], pinnedEventIds: Set<string>): EventType[] => {
                if (pinnedEventIds.size === 0) {
                    return activeFilteredEvents
                }
                return activeFilteredEvents.filter((e: EventType) => !e.uuid || !pinnedEventIds.has(e.uuid))
            },
        ],

        expandedProperties: [
            (s) => [s.expandedEvent, s.events, s.hidePostHogProperties, s.hidePostHogFlags],
            (
                expandedEvent: string | null | undefined,
                events: EventType[],
                hidePostHogProperties: boolean,
                hidePostHogFlags: boolean
            ) => {
                if (!expandedEvent) {
                    return []
                }
                const allProperties = events.find((e) => e.uuid === expandedEvent)?.properties
                if (!allProperties) {
                    return []
                }

                const posthogPropertiesFiltered = hidePostHogProperties
                    ? Object.fromEntries(
                          Object.entries(allProperties).filter(([key]) => {
                              const isPostHogProperty = key.startsWith('$') && PROPERTY_KEYS.includes(key)
                              const isNonDollarPostHogProperty = CLOUD_INTERNAL_POSTHOG_PROPERTY_KEYS.includes(key)
                              return !isPostHogProperty && !isNonDollarPostHogProperty
                          })
                      )
                    : allProperties

                const posthogFlagsFiltered = hidePostHogFlags
                    ? Object.fromEntries(
                          Object.entries(posthogPropertiesFiltered).filter(([key]) => {
                              if (key === '$active_feature_flags') {
                                  return false
                              } else if (key.startsWith('$feature/')) {
                                  return false
                              }

                              return true
                          })
                      )
                    : posthogPropertiesFiltered

                return posthogFlagsFiltered
            },
        ],

        exportableEvents: [
            (s) => [s.activeFilteredEvents],
            (activeFilteredEvents: EventType[]): object[] => {
                return activeFilteredEvents.map((e: EventType) => ({
                    event: e.event,
                    timestamp: e.timestamp,
                    properties: e.properties,
                    uuid: e.uuid,
                }))
            },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setSearchText: () => {
            if (cache.searchQuery === values.searchText) {
                return
            }
            cache.searchQuery = values.searchText
            cache.disposables.dispose('regexSearch')
            cache.searchSnapshot = undefined
            actions.resetRegexSearch()
            actions.refreshRegexSearch()
        },
        addEvent: () => {
            actions.refreshRegexSearch()
        },
        togglePaused: () => {
            cache.disposables.dispose('regexSearch')
            cache.searchSnapshot = undefined
            actions.setSearchPending(false)
            actions.refreshRegexSearch()
        },
        clearEvents: () => {
            cache.disposables.dispose('regexSearch')
            cache.searchSnapshot = undefined
        },
        refreshRegexSearch: () => {
            const regex = regexSearch(values.searchText)
            if (!regex || values.searchError || values.literalSearch || cache.searchRunning) {
                return
            }
            const snapshot = values.visibleEvents
            const previous: EventType[] | undefined = cache.searchSnapshot
            if (
                !snapshot.length ||
                (previous?.length === snapshot.length && previous.every((event, index) => event === snapshot[index]))
            ) {
                return
            }
            cache.searchSnapshot = snapshot
            const manager: DisposablesManager = cache.disposables
            const context = getContext()
            actions.setSearchPending(true)
            manager.add(
                () => {
                    let active = true
                    cache.searchRunning = true
                    const request = startRegexMatching(snapshot.map((event) => ({ ...regex, subject: event.event })))
                    void request.promise.then((result) => {
                        if (!active || manager.isDisposed || getContext() !== context) {
                            return
                        }
                        manager.dispose('regexSearch')
                        if (result.status === 'error') {
                            actions.setSearchResult([], result.error, false)
                            return
                        }
                        const literal = result.results.some((check) => 'error' in check)
                        const matches = snapshot.filter((_, index) => {
                            const check = result.results[index]
                            return 'matches' in check && check.matches
                        })
                        actions.setSearchResult(matches, null, literal)
                        // Publish this batch before catching up so a continuous stream cannot starve the list.
                        actions.refreshRegexSearch()
                    })
                    return () => {
                        active = false
                        cache.searchRunning = false
                        request.cancel()
                    }
                },
                'regexSearch',
                { pauseOnPageHidden: false }
            )
        },
    })),
    afterMount(({ values, actions, cache }) => {
        cache.searchQuery = values.searchText
        cache.searchRunning = false
        cache.searchSnapshot = undefined
        cache.disposables.add(() => {
            return values.posthog?.on('eventCaptured', (e) => {
                actions.addEvent(e)
            })
        }, 'posthogEventListener')
    }),
    permanentlyMount(),
])
