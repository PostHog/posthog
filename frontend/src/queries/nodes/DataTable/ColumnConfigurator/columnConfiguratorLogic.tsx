export const columnConfiguratorLogic = kea<columnConfiguratorLogicType>([
    props({} as ColumnConfiguratorLogicProps),
    path(['queries', 'nodes', 'DataTable', 'columnConfiguratorLogic']),
    key((props) => props.key),
    connect(() => ({
        actions: [eventUsageLogic, ['reportDataTableColumnsUpdated'], groupsModel, ['setDefaultColumns']],
    })),
    actions({
        showModal: true,
        hideModal: true,
        selectColumn: (column: string) => ({ column }),
        unselectColumn: (column: string) => ({ column }),
        setColumns: (columns: string[]) => ({ columns }),
        moveColumn: (oldIndex: number, newIndex: number) => ({ oldIndex, newIndex }),
        save: true,
        toggleSaveAsDefault: true,
    }),
    selectors(() => ({
        context: [
            () => [(_, props) => props.context],
            (context: NonNullable<ColumnConfiguratorLogicProps['context']>) => context,
        ],
    })),
    loaders(({ props }) => ({
        savedColumnConfigurations: [
            { private: null, shared: null } as SavedColumnConfigurations,
            {
                loadSavedColumnConfigurations: async (): Promise<SavedColumnConfigurations> => {
                    if (!props.contextKey) {
                        return { private: null, shared: null }
                    }
                    const response = await api.columnConfigurations.list({
                        teamId: teamLogic.values.currentTeamId || undefined,
                        context_key: props.contextKey,
                    })
                    const configurations: SavedColumnConfigurations = { private: null, shared: null }
                    for (const result of response.results ?? []) {
                        const visibility =
                            result.visibility === ColumnConfigurationVisibilityEnumApi.Private
                                ? ColumnConfigurationVisibilityEnumApi.Private
                                : ColumnConfigurationVisibilityEnumApi.Shared
                        // The list is ordered newest first within a visibility — keep the first of each
                        if (!configurations[visibility]) {
                            configurations[visibility] = { id: result.id, columns: result.columns || [] }
                        }
                    }
                    return configurations
                },
            },
        ],
    })),
    reducers(({ props }) => ({
        saveAsDefault: [
            false,
            {
                toggleSaveAsDefault: (state) => !state,
            },
        ],
        modalVisible: [
            false,
            {
                showModal: () => true,
                hideModal: () => false,
                save: () => false,
            },
        ],
        columns: [
            props.columns,
            {
                setColumns: (_, { columns }) => columns,
                selectColumn: (state, { column }) => Array.from(new Set([...state, column])),
                unselectColumn: (state, { column }) => state.filter((c) => c !== column),
                moveColumn: (state, { oldIndex, newIndex }) => {
                    const newColumns = [...state]
                    const [removed] = newColumns.splice(oldIndex, 1)
                    newColumns.splice(newIndex, 0, removed)
                    return newColumns
                },
            },
        ],
    })),
    propsChanged(({ actions, props }, oldProps) => {
        if (JSON.stringify(props.columns) !== JSON.stringify(oldProps.columns)) {
            actions.setColumns(props.columns)
        }
    }),
    listeners(({ actions, values, props }) => ({
        loadSavedColumnConfigurationsSuccess: ({ savedColumnConfigurations }) => {
            // A personal configuration shadows the team-wide one
            const applicable = savedColumnConfigurations.private ?? savedColumnConfigurations.shared
            if (applicable) {
                props.setColumns(applicable.columns)
            }
        },
        save: async () => {
            actions.reportDataTableColumnsUpdated(props.contextKey ?? props.context?.type ?? 'live_events')

            // With a context key the selection is persisted through the column configurations API on
            // every save — personal by default, team-wide when the user opted into that.
            if (props.contextKey && props.isPersistent && !props.showTableViews) {
                const visibility = values.saveAsDefault
                    ? ColumnConfigurationVisibilityEnumApi.Shared
                    : ColumnConfigurationVisibilityEnumApi.Private
                const existing = values.savedColumnConfigurations[visibility]
                try {
                    if (existing) {
                        await api.columnConfigurations.update({
                            teamId: teamLogic.values.currentTeamId || undefined,
                            id: existing.id,
                            data: { columns: values.columns },
                        })
                        actions.loadSavedColumnConfigurationsSuccess({
                            ...values.savedColumnConfigurations,
                            [visibility]: { id: existing.id, columns: values.columns },
                        })
                    } else {
                        const response = await api.columnConfigurations.create({
                            teamId: teamLogic.values.currentTeamId || undefined,
                            data: {
                                context_key: props.contextKey,
                                columns: values.columns,
                                visibility,
                            },
                        })
                        actions.loadSavedColumnConfigurationsSuccess({
                            ...values.savedColumnConfigurations,
                            [visibility]: { id: response.id, columns: response.columns || [] },
                        })
                    }

                    lemonToast.success(
                        visibility === ColumnConfigurationVisibilityEnumApi.Shared
                            ? 'Default columns saved'
                            : 'Columns saved'
                    )
                } catch (error: any) {
                    console.error('Error saving column configuration:', error)
                    lemonToast.error(error.detail || 'Failed to save column configuration')
                }
                props.setColumns(values.columns)
                return
            }

            if (!props.isPersistent || !values.saveAsDefault) {
                props.setColumns(values.columns)
                return
            }

            if (props.context?.type === 'groups' && typeof props.context.groupTypeIndex === 'number') {
                try {
                    actions.setDefaultColumns({
                        groupTypeIndex: props.context.groupTypeIndex,
                        defaultColumns: values.columns,
                    })
                    lemonToast.success('Default columns saved for this group type')
                } catch (error) {
                    console.error('Error saving default columns to group type:', error)
                    lemonToast.error('Failed to save columns to group type')
                }
            } else if (props.context?.type === 'event_definition' && props.context.eventDefinitionId) {
                try {
                    await api.eventDefinitions.update({
                        eventDefinitionId: props.context.eventDefinitionId,
                        eventDefinitionData: {
                            default_columns: values.columns,
                        },
                    })
                    lemonToast.success('Default columns saved for this event')
                } catch (error: any) {
                    console.error('Error saving default columns to event definition:', error)
                    lemonToast.error(error.detail || 'Failed to save columns to event definition')
                }
            } else {
                // Team-wide default columns
                teamLogic.actions.updateCurrentTeam({ live_events_columns: [HOGQL_COLUMNS_KEY, ...values.columns] })
            }

            // Always update the columns in the query
            props.setColumns(values.columns)
        },
    })),
    afterMount(({ actions, props }) => {
        // Only load saved column configuration if table views aren't handling persistence
        if (props.contextKey && !props.showTableViews) {
            actions.loadSavedColumnConfigurations()
        }
    }),
])
