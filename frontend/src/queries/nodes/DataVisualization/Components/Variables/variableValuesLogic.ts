import { LogicWrapper, MakeLogicType, afterMount, kea, key, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { performQuery } from '~/queries/query'
import { HogQLQuery, NodeKind } from '~/queries/schema/schema-general'

import { ListVariable } from '../../types'
import { getListVariableValues } from './variableUtils'

export interface VariableValuesLogicProps {
    variable: ListVariable
    loadOnMount: boolean
}

export interface VariableOption {
    value: string
    label: string
}

// Identifies which (connection, query) pair a load ran against, so consumers can tell
// whether the loaded options still match the variable being edited. Null means static options.
export const getValuesQueryKey = (variable: ListVariable): string | null => {
    const valuesQuery = variable.values_query?.trim()
    if (!valuesQuery) {
        return null
    }
    return `${variable.values_query_connection_id ?? ''}\n${valuesQuery}`
}

const isScalar = (value: unknown): value is string | number | boolean =>
    ['string', 'number', 'boolean'].includes(typeof value)

export const queryResultsToVariableOptions = (results: unknown): VariableOption[] => {
    if (!Array.isArray(results)) {
        return []
    }

    const options: VariableOption[] = []
    const seenValues = new Set<string>()
    for (const row of results) {
        const rawValue = Array.isArray(row) ? row[0] : row
        if (!isScalar(rawValue)) {
            continue
        }
        const value = String(rawValue)
        if (seenValues.has(value)) {
            continue
        }
        seenValues.add(value)
        const rawLabel = Array.isArray(row) ? row[1] : undefined
        options.push({ value, label: isScalar(rawLabel) ? String(rawLabel) : value })
    }

    return options
}

export const getStaticVariableOptions = (variable: ListVariable): VariableOption[] =>
    getListVariableValues(variable).map((value) => ({ value, label: value }))

export const loadListVariableOptions = async (variable: ListVariable): Promise<VariableOption[]> => {
    const valuesQuery = variable.values_query?.trim()
    if (!valuesQuery) {
        return getStaticVariableOptions(variable)
    }

    const response = await performQuery<HogQLQuery>({
        kind: NodeKind.HogQLQuery,
        query: valuesQuery,
        ...(variable.values_query_connection_id ? { connectionId: variable.values_query_connection_id } : {}),
    })

    return queryResultsToVariableOptions(response.results).slice(0, 1000)
}

