export interface variableValuesLogicMeta {
    key: string
}

export type variableValuesLogicType = MakeLogicType<
    variableValuesLogicValues,
    variableValuesLogicActions,
    VariableValuesLogicProps,
    variableValuesLogicMeta
>

export const variableValuesLogic: LogicWrapper<variableValuesLogicType> = kea<variableValuesLogicType>([
    props({} as VariableValuesLogicProps),
    key((props) => props.variable.id || 'new'),
    path((key) => ['queries', 'nodes', 'DataVisualization', 'Variables', 'variableValuesLogic', key]),
    loaders(({ props }) => ({
        variableOptions: [
            EMPTY_LIST_VARIABLE_OPTIONS,
            {
                loadVariableOptions: async (variable?: ListVariable) =>
                    loadListVariableOptions(variable ?? props.variable),
            },
        ],
    })),
    reducers(({ props }) => ({
        requestedValuesQueryKey: [
            null as string | null,
            {
                loadVariableOptions: (_, variable) => getValuesQueryKey(variable ?? props.variable),
            },
        ],
        variableOptionsError: [
            null as string | null,
            {
                loadVariableOptions: () => null,
                loadVariableOptionsSuccess: () => null,
                loadVariableOptionsFailure: (_, { error, errorObject }) => errorObject?.detail ?? error,
            },
        ],
    })),
    afterMount(({ actions, props }) => {
        if (props.loadOnMount) {
            actions.loadVariableOptions(props.variable)
        }
    }),
])
