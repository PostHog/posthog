import { LogicWrapper, MakeLogicType, afterMount, kea, key, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { performQuery } from '~/queries/query'
import { HogQLQuery, NodeKind } from '~/queries/schema/schema-general'

import { ListVariable } from '../../types'
import { getListVariableValues } from './variableUtils'

export interface VariableValuesLogicProps {
    key: string
    variable: ListVariable
    loadOnMount: boolean
}

export const queryResultsToVariableOptions = (results: unknown): string[] => {
    if (!Array.isArray(results)) {
        return []
    }

    const values = results
        .map((row) => (Array.isArray(row) ? row[0] : row))
        .filter((value): value is string | number | boolean => ['string', 'number', 'boolean'].includes(typeof value))
        .map(String)

    return Array.from(new Set(values))
}

export const loadListVariableOptions = async (variable: ListVariable): Promise<string[]> => {
    const valuesQuery = variable.values_query?.trim()
    if (!valuesQuery) {
        return getListVariableValues(variable)
    }

    const response = await performQuery<HogQLQuery>({
        kind: NodeKind.HogQLQuery,
        query: valuesQuery,
    })

    return queryResultsToVariableOptions(response.results).slice(0, 1000)
}

