export interface DataNodeRegisteredProps {
    id: string
    loadData: (refresh?: RefreshType) => void
    cancelQuery: () => void
}

export interface CollectionNodeLoadMeta {
    isCached?: boolean
}

export interface DataNodeCollectionProps {
    key: string
}

export interface DataNodeStatus {
    isLoading: boolean
    hasError: boolean
}

export type DataNodeStatusMap = Record<string, DataNodeStatus | undefined>

export type DataCollectionLoadTrigger = 'initial_load' | 'refresh' | 'update'

interface DataCollectionLoadTile {
    kind: string | null
    status: 'loading' | 'success' | 'failure'
    cached: boolean
}

interface DataCollectionLoadCycle {
    id: string
    startedAt: number
    scene: string | null
    trigger: DataCollectionLoadTrigger
    tiles: Map<string, DataCollectionLoadTile>
    lastTileId: string | null
    visitId: string | null
    hiddenMs: number
    reportedHidden: boolean
    firstTileMs: number | null
    kindReadyMs: Record<string, number>
    requeriedWhileLoading: number
}

interface DataCollectionPageVisit {
    id: string
    startedAt: number
    cycles: number
    tilesMounted: number
    reported: boolean
}

