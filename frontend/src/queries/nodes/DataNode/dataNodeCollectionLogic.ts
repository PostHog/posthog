import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { sceneLogic } from 'scenes/sceneLogic'

import { isPageCollection } from '~/queries/nodes/DataNode/pageCollections'
import { RefreshType } from '~/queries/schema/schema-general'

export interface DataNodeRegisteredProps {
    id: string
    loadData: (refresh?: RefreshType) => void
    cancelQuery: () => void
    kind?: string
}

export interface CollectionNodeLoadMeta {
    isCached?: boolean
}

export interface DataNodeCollectionProps {
    key: string
}

export interface DataNodeStatus {
    isLoading: boolean
    hasError: boolean
}

export type DataNodeStatusMap = Record<string, DataNodeStatus | undefined>

export type DataCollectionLoadTrigger = 'initial_load' | 'refresh' | 'update'

export type DataCollectionTileStatus = 'success' | 'failure' | 'unmounted'

// Renaming these breaks the dashboards and alerts built on them — pin, don't rename.
export const DATA_COLLECTION_LOAD_STARTED_EVENT = 'data_collection_load_started'
export const DATA_COLLECTION_SETTLED_EVENT = 'data_collection_settled'
export const DATA_COLLECTION_ABANDONED_EVENT = 'data_collection_abandoned'

interface DataCollectionLoadCycle {
    startedAt: number
    /** Captured when the cycle opens: navigating away flips the active scene before the tiles unmount. */
    scene: string | null
    trigger: DataCollectionLoadTrigger
    participatingTileIds: Set<string>
    settledTileIds: Set<string>
    unmountedTileIds: Set<string>
    failedTileCount: number
    cachedTileCount: number
    lastTileId: string | null
    lastTileKind: string | null
    lastTileStatus: DataCollectionTileStatus | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataNodeCollectionLogicValues {
    areAnyLoading: boolean
    collectionNodeStatus: DataNodeStatusMap
    mountedDataNodes: DataNodeRegisteredProps[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataNodeCollectionLogicActions {
    cancelAllLoading: () => {}
    collectionNodeLoadData: (id: string) => {
        id: string
    }
    collectionNodeLoadDataFailure: (id: string) => {
        id: string
    }
    collectionNodeLoadDataSuccess: (
        id: string,
        meta?: CollectionNodeLoadMeta
    ) => {
        id: string
        meta: CollectionNodeLoadMeta | undefined
    }
    mountDataNode: (
        id: string,
        props: DataNodeRegisteredProps
    ) => {
        id: string
        props: DataNodeRegisteredProps
    }
    reloadAll: () => {}
    unmountDataNode: (id: string) => {
        id: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataNodeCollectionLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        areAnyLoading: (collectionNodeStatus: DataNodeStatusMap) => boolean
    }
}

export type dataNodeCollectionLogicType = MakeLogicType<
    dataNodeCollectionLogicValues,
    dataNodeCollectionLogicActions,
    DataNodeCollectionProps,
    dataNodeCollectionLogicMeta
>

export const dataNodeCollectionLogic = kea<dataNodeCollectionLogicType>([
    path(['queries', 'nodes', 'dataNodeCollectionLogic']),
    props({} as DataNodeCollectionProps),
    key((props: DataNodeCollectionProps) => {
        return props.key
    }),
    actions({
        mountDataNode: (id: string, props: DataNodeRegisteredProps) => ({ id, props }),
        unmountDataNode: (id: string) => ({ id }),
        reloadAll: () => ({}),
        cancelAllLoading: () => ({}),
        collectionNodeLoadData: (id: string) => ({ id }),
        collectionNodeLoadDataSuccess: (id: string, meta?: CollectionNodeLoadMeta) => ({ id, meta }),
        collectionNodeLoadDataFailure: (id: string) => ({ id }),
    }),
    reducers({
        mountedDataNodes: [
            [] as DataNodeRegisteredProps[],
            {
                mountDataNode: (state, payload) => {
                    const filtered = state.filter((node) => node.id !== payload.id)
                    return [...filtered, payload.props]
                },
                unmountDataNode: (state, payload) => state.filter((node) => node.id !== payload.id),
            },
        ],
        collectionNodeStatus: [
            {} as DataNodeStatusMap,
            {
                mountDataNode: (state, payload) => {
                    // A node starts loading before it registers, so registering must not clear that.
                    return { ...state, [payload.id]: state[payload.id] ?? { isLoading: false, hasError: false } }
                },
                unmountDataNode: (state, payload) => {
                    const { [payload.id]: _discard, ...rest } = state
                    return rest
                },
                collectionNodeLoadData: (state, payload) => {
                    return { ...state, [payload.id]: { isLoading: true, hasError: false } }
                },
                collectionNodeLoadDataSuccess: (state, payload) => {
                    return { ...state, [payload.id]: { isLoading: false, hasError: false } }
                },
                collectionNodeLoadDataFailure: (state, payload) => {
                    return { ...state, [payload.id]: { isLoading: false, hasError: true } }
                },
            },
        ],
    }),
    selectors({
        areAnyLoading: [
            (s) => [s.collectionNodeStatus],
            (collectionNodeStatus: DataNodeStatusMap) => {
                return Object.values(collectionNodeStatus).some((status) => {
                    return status?.isLoading
                })
            },
        ],
    }),
    listeners(({ values, props, cache }) => {
        const capture = (event: string, properties: Record<string, unknown>): void => {
            // `posthog.capture` is absent inside the toolbar bundle.
            if (isPageCollection(props.key) && posthog.capture) {
                posthog.capture(event, properties)
            }
        }

        const cycleProps = (cycle: DataCollectionLoadCycle): Record<string, unknown> => ({
            collection_key: props.key,
            scene: cycle.scene,
            trigger: cycle.trigger,
            time_since_mount_ms: Math.round(performance.now() - cache.mountedAt),
        })

        const isTileInFlight = (cycle: DataCollectionLoadCycle, id: string): boolean =>
            cycle.participatingTileIds.has(id) && !cycle.settledTileIds.has(id) && !cycle.unmountedTileIds.has(id)

        const noteLastTile = (cycle: DataCollectionLoadCycle, id: string, status: DataCollectionTileStatus): void => {
            cycle.lastTileId = id
            cycle.lastTileKind = values.mountedDataNodes.find((node) => node.id === id)?.kind ?? null
            cycle.lastTileStatus = status
        }

        const closeCycle = (): void => {
            cache.cycle = null
            cache.completedCycles += 1
        }

        const settle = (cycle: DataCollectionLoadCycle): void => {
            capture(DATA_COLLECTION_SETTLED_EVENT, {
                ...cycleProps(cycle),
                duration_ms: Math.round(performance.now() - cycle.startedAt),
                tile_count: cycle.participatingTileIds.size,
                failed_tile_count: cycle.failedTileCount,
                cached_tile_count: cycle.cachedTileCount,
                unmounted_tile_count: cycle.unmountedTileIds.size,
                last_tile_id: cycle.lastTileId,
                last_tile_kind: cycle.lastTileKind,
                last_tile_status: cycle.lastTileStatus,
            })
            closeCycle()
        }

        const settleIfDone = (cycle: DataCollectionLoadCycle): void => {
            if (!values.areAnyLoading) {
                settle(cycle)
            }
        }

        return {
            reloadAll: () => {
                // Consumed synchronously by the collectionNodeLoadData each loadData dispatches below.
                cache.pendingTrigger = 'refresh'
                // We want to force refresh all nodes, so we use 'force_async' to bypass cache
                // The loadData function in each node will handle converting this to the appropriate type
                // based on whether the node is an insight or not
                values.mountedDataNodes.forEach((node) => node.loadData('force_async'))
                cache.pendingTrigger = null
            },
            cancelAllLoading: () => {
                values.mountedDataNodes.forEach((node) => {
                    const status = values.collectionNodeStatus[node.id]
                    if (status?.isLoading) {
                        node.cancelQuery()
                    }
                })
            },
            collectionNodeLoadData: ({ id }) => {
                if (!cache.cycle) {
                    const cycle: DataCollectionLoadCycle = {
                        startedAt: performance.now(),
                        scene: sceneLogic.findMounted()?.values.activeSceneId ?? null,
                        trigger: cache.pendingTrigger ?? (cache.completedCycles === 0 ? 'initial_load' : 'update'),
                        participatingTileIds: new Set([id]),
                        settledTileIds: new Set(),
                        unmountedTileIds: new Set(),
                        failedTileCount: 0,
                        cachedTileCount: 0,
                        lastTileId: null,
                        lastTileKind: null,
                        lastTileStatus: null,
                    }
                    cache.cycle = cycle
                    capture(DATA_COLLECTION_LOAD_STARTED_EVENT, {
                        ...cycleProps(cycle),
                        mounted_tile_count: values.mountedDataNodes.length,
                    })
                    return
                }
                cache.cycle.participatingTileIds.add(id)
            },
            collectionNodeLoadDataSuccess: ({ id, meta }) => {
                const cycle = cache.cycle
                if (!cycle) {
                    return
                }
                cycle.settledTileIds.add(id)
                if (meta?.isCached) {
                    cycle.cachedTileCount += 1
                }
                noteLastTile(cycle, id, 'success')
                settleIfDone(cycle)
            },
            collectionNodeLoadDataFailure: ({ id }) => {
                const cycle = cache.cycle
                if (!cycle) {
                    return
                }
                cycle.settledTileIds.add(id)
                cycle.failedTileCount += 1
                noteLastTile(cycle, id, 'failure')
                settleIfDone(cycle)
            },
            unmountDataNode: ({ id }) => {
                const cycle = cache.cycle
                if (!cycle || !isTileInFlight(cycle, id)) {
                    return
                }
                // Navigating away unmounts every node before the collection itself, so abandonment has to
                // be caught here rather than in beforeUnmount, where nothing is left to observe.
                noteLastTile(cycle, id, 'unmounted')
                cycle.unmountedTileIds.add(id)
                if (values.mountedDataNodes.length === 0) {
                    capture(DATA_COLLECTION_ABANDONED_EVENT, {
                        ...cycleProps(cycle),
                        duration_ms: Math.round(performance.now() - cycle.startedAt),
                        tile_count: cycle.participatingTileIds.size,
                        tiles_still_loading: cycle.participatingTileIds.size - cycle.settledTileIds.size,
                    })
                    closeCycle()
                    return
                }
                settleIfDone(cycle)
            },
        }
    }),
    afterMount(({ cache }) => {
        cache.mountedAt = performance.now()
        cache.cycle = null
        cache.completedCycles = 0
        cache.pendingTrigger = null
    }),
])
