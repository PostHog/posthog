import { MakeLogicType, actions, afterMount, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import posthog, { CaptureOptions } from 'posthog-js'

import { PageLoadTimeToSeeData } from 'lib/internalMetrics'
import { uuid } from 'lib/utils/dom'
import { sceneLogic } from 'scenes/sceneLogic'

import { isPageCollection } from '~/queries/nodes/DataNode/pageCollections'
import { RefreshType } from '~/queries/schema/schema-general'

export interface DataNodeRegisteredProps {
    id: string
    loadData: (refresh?: RefreshType) => void
    cancelQuery: () => void
}

export interface CollectionNodeLoadMeta {
    isCached?: boolean
}

export interface DataNodeCollectionProps {
    key: string
}

export interface DataNodeStatus {
    isLoading: boolean
    hasError: boolean
}

export type DataNodeStatusMap = Record<string, DataNodeStatus | undefined>

export type DataCollectionLoadTrigger = 'initial_load' | 'refresh' | 'update'

interface DataCollectionLoadTile {
    kind: string | null
    status: 'loading' | 'success' | 'failure'
    cached: boolean
}

interface DataCollectionLoadCycle {
    id: string
    startedAt: number
    scene: string | null
    trigger: DataCollectionLoadTrigger
    tiles: Map<string, DataCollectionLoadTile>
    lastTileId: string | null
}

