// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface dataNodeCollectionLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        areAnyLoading: (collectionNodeStatus: DataNodeStatusMap) => boolean
    }
}

export type dataNodeCollectionLogicType = MakeLogicType<
    dataNodeCollectionLogicValues,
    dataNodeCollectionLogicActions,
    DataNodeCollectionProps,
    dataNodeCollectionLogicMeta
>

export const dataNodeCollectionLogic = kea<dataNodeCollectionLogicType>([
    path(['queries', 'nodes', 'dataNodeCollectionLogic']),
    props({} as DataNodeCollectionProps),
    key((props: DataNodeCollectionProps) => {
        return props.key
    }),
    actions({
        mountDataNode: (id: string, props: DataNodeRegisteredProps) => ({ id, props }),
        unmountDataNode: (id: string) => ({ id }),
        reloadAll: () => ({}),
        cancelAllLoading: () => ({}),
        collectionNodeLoadData: (id: string, kind?: string) => ({ id, kind }),
        collectionNodeLoadDataSuccess: (id: string, meta?: CollectionNodeLoadMeta) => ({ id, meta }),
        collectionNodeLoadDataFailure: (id: string) => ({ id }),
        pageHidden: true,
    }),
    reducers({
        mountedDataNodes: [
            [] as DataNodeRegisteredProps[],
            {
                mountDataNode: (state, payload) => {
                    const filtered = state.filter((node) => node.id !== payload.id)
                    return [...filtered, payload.props]
                },
                unmountDataNode: (state, payload) => state.filter((node) => node.id !== payload.id),
            },
        ],
        collectionNodeStatus: [
            {} as DataNodeStatusMap,
            {
                mountDataNode: (state, payload) => {
                    return { ...state, [payload.id]: state[payload.id] ?? { isLoading: false, hasError: false } }
                },
                unmountDataNode: (state, payload) => {
                    const { [payload.id]: _discard, ...rest } = state
                    return rest
                },
                collectionNodeLoadData: (state, payload) => {
                    return { ...state, [payload.id]: { isLoading: true, hasError: false } }
                },
                collectionNodeLoadDataSuccess: (state, payload) => {
                    return { ...state, [payload.id]: { isLoading: false, hasError: false } }
                },
                collectionNodeLoadDataFailure: (state, payload) => {
                    return { ...state, [payload.id]: { isLoading: false, hasError: true } }
                },
            },
        ],
    }),
    selectors({
        areAnyLoading: [
            (s) => [s.collectionNodeStatus],
            (collectionNodeStatus: DataNodeStatusMap) => {
                return Object.values(collectionNodeStatus).some((status) => {
                    return status?.isLoading
                })
            },
        ],
    }),
    listeners(({ values, props, cache }) => {
        const countTiles = (
            cycle: DataCollectionLoadCycle,
            matches: (tile: DataCollectionLoadTile) => boolean
        ): number => [...cycle.tiles.values()].filter(matches).length

        const report = (
            cycle: DataCollectionLoadCycle,
            outcome: Partial<PageLoadTimeToSeeData>,
            options?: CaptureOptions
        ): void => {
            if (!isPageCollection(props.key) || !posthog.capture) {
                return
            }
            const payload: PageLoadTimeToSeeData = {
                type: 'page_load',
                context: props.key,
                action: cycle.trigger,
                primary_interaction_id: cycle.id,
                time_to_see_data_ms: Math.round(performance.now() - cycle.startedAt),
                insights_fetched: cycle.tiles.size,
                insights_fetched_cached: countTiles(cycle, (tile) => tile.cached),
                scene: cycle.scene,
                time_since_mount_ms: Math.round(performance.now() - cache.mountedAt),
                ...outcome,
            }
            posthog.capture('time to see data', payload, options)
        }

        const finishTile = (id: string, status: 'success' | 'failure', cached = false): void => {
            const cycle = cache.cycle
            if (!cycle) {
                return
            }
            cycle.tiles.set(id, { kind: cycle.tiles.get(id)?.kind ?? null, status, cached })
            cycle.lastTileId = id
            if (!values.areAnyLoading) {
                settle(cycle)
            }
        }

        const closeCycle = (): void => {
            cache.cycle = null
            cache.completedCycles += 1
        }

        const settle = (cycle: DataCollectionLoadCycle): void => {
            const failedTileCount = countTiles(cycle, (tile) => tile.status === 'failure')
            const lastTile = cycle.lastTileId ? cycle.tiles.get(cycle.lastTileId) : undefined
            report(cycle, {
                status: failedTileCount > 0 ? 'failure' : 'success',
                failed_tile_count: failedTileCount,
                last_tile_id: cycle.lastTileId,
                last_tile_kind: lastTile?.kind ?? null,
                last_tile_status: lastTile?.status ?? null,
            })
            closeCycle()
        }

        const abandon = (
            cycle: DataCollectionLoadCycle,
            reason: NonNullable<PageLoadTimeToSeeData['cancel_reason']>,
            options?: CaptureOptions
        ): void => {
            report(
                cycle,
                {
                    status: 'cancelled',
                    cancel_reason: reason,
                    tiles_still_loading: countTiles(cycle, (tile) => tile.status === 'loading'),
                },
                options
            )
            closeCycle()
        }

        return {
            reloadAll: () => {
                if (cache.cycle) {
                    abandon(cache.cycle, 'refreshed')
                }
                cache.pendingTrigger = 'refresh'
                // We want to force refresh all nodes, so we use 'force_async' to bypass cache
                // The loadData function in each node will handle converting this to the appropriate type
                // based on whether the node is an insight or not
                values.mountedDataNodes.forEach((node) => node.loadData('force_async'))
                cache.pendingTrigger = null
            },
            cancelAllLoading: () => {
                values.mountedDataNodes.forEach((node) => {
                    const status = values.collectionNodeStatus[node.id]
                    if (status?.isLoading) {
                        node.cancelQuery()
                    }
                })
            },
            collectionNodeLoadData: ({ id, kind }) => {
                if (!cache.cycle) {
                    cache.cycle = {
                        id: uuid(),
                        startedAt: performance.now(),
                        scene: sceneLogic.findMounted()?.values.activeSceneId ?? null,
                        trigger: cache.pendingTrigger ?? (cache.completedCycles === 0 ? 'initial_load' : 'update'),
                        tiles: new Map(),
                        lastTileId: null,
                    } satisfies DataCollectionLoadCycle
                }
                cache.cycle.tiles.set(id, { kind: kind ?? null, status: 'loading', cached: false })
            },
            collectionNodeLoadDataSuccess: ({ id, meta }) => {
                finishTile(id, 'success', !!meta?.isCached)
            },
            collectionNodeLoadDataFailure: ({ id }) => {
                finishTile(id, 'failure')
            },
            unmountDataNode: ({ id }) => {
                if (cache.cycle?.tiles.get(id)?.status === 'loading') {
                    abandon(cache.cycle, 'navigated_away')
                }
            },
            pageHidden: () => {
                if (cache.cycle) {
                    abandon(cache.cycle, 'left_app', { transport: 'sendBeacon' })
                }
            },
        }
    }),
    afterMount(({ actions, cache }) => {
        cache.mountedAt = performance.now()
        cache.cycle = null
        cache.completedCycles = 0
        cache.pendingTrigger = null
        cache.disposables.add(
            () => {
                window.addEventListener('pagehide', actions.pageHidden)
                return () => window.removeEventListener('pagehide', actions.pageHidden)
            },
            'pagehide',
            { pauseOnPageHidden: false }
        )
    }),
])
