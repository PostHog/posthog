function hasFeedbackQuestions(survey: Survey): boolean {
    const [choice, detail] = survey.questions
    return (
        survey.questions.length === 2 &&
        choice.type === SurveyQuestionType.Rating &&
        !!choice.id &&
        choice.scale === SURVEY_RATING_SCALE.THUMB_2_POINT &&
        choice.display === 'emoji' &&
        detail.type === SurveyQuestionType.Open &&
        !!detail.id &&
        !!detail.optional
    )
}

export const surveyFeedbackPromptLogic: LogicWrapper<surveyFeedbackPromptLogicType> =
    kea<surveyFeedbackPromptLogicType>([
        props({ eligible: true } as SurveyFeedbackPromptLogicProps),
        key(({ surveyId, userId, contextKey, prompt }) =>
            JSON.stringify([surveyId, userId, prompt.entryPoint, contextKey])
        ),
        path((key) => ['lib', 'logic', 'surveyFeedbackPrompt', 'surveyFeedbackPromptLogic', key]),
        connect(({ cooldownStorageKey, userId }: SurveyFeedbackPromptLogicProps) => ({
            values: [surveyFeedbackCooldownLogic({ storageKey: `${cooldownStorageKey}:${userId}` }), ['lastPromptAt']],
            actions: [surveyFeedbackCooldownLogic({ storageKey: `${cooldownStorageKey}:${userId}` }), ['recordPrompt']],
        })),
        actions({
            schedulePrompt: (survey: Survey | null) => ({ survey }),
            showPrompt: (survey: Survey, timestamp: number, submissionId: string) => ({
                survey,
                timestamp,
                submissionId,
            }),
            recordImpression: true,
            impressionRecorded: true,
            dismissPrompt: true,
            hidePrompt: true,
            setDetail: (detail: string) => ({ detail }),
            submitResponse: (answer: string, completed: boolean) => ({ answer, completed }),
            responseQueued: (answer: string, completed: boolean) => ({ answer, completed }),
            responseFailed: true,
            captureStarted: true,
        }),
        reducers(({ props }) => ({
            prompt: [props.prompt, { showPrompt: () => ({ ...props.prompt }) }],
            visible: [false, { showPrompt: () => true, hidePrompt: () => false }],
            impressionRecorded: [false, { impressionRecorded: () => true }],
            survey: [null as Survey | null, { showPrompt: (_, { survey }) => survey }],
            submissionId: ['', { showPrompt: (_, { submissionId }) => submissionId }],
            answer: ['', { responseQueued: (_, { answer }) => answer }],
            detail: ['', { setDetail: (_, { detail }) => detail }],
            completed: [false, { responseQueued: (_, { completed }) => completed }],
            submitting: [
                false,
                { captureStarted: () => true, responseQueued: () => false, responseFailed: () => false },
            ],
            error: [false, { captureStarted: () => false, responseFailed: () => true }],
        })),
        selectors({
            surveyEventProperties: [
                (s) => [s.survey, s.submissionId, s.prompt],
                (
                    survey: Survey | null,
                    submissionId: string,
                    prompt: SurveyFeedbackPromptConfig
                ): Record<string, unknown> => ({
                    ...prompt.properties,
                    feedback_surface: prompt.surface,
                    feedback_entry_point: prompt.entryPoint,
                    feedback_question_version: prompt.version,
                    feedback_question: prompt.question,
                    feedback_followup_question: prompt.followUpQuestion,
                    [SurveyEventProperties.SURVEY_ID]: survey?.id,
                    $survey_name: survey?.name,
                    [SurveyEventProperties.SURVEY_SUBMISSION_ID]: submissionId,
                    $survey_questions: survey?.questions.map(({ id }, index) => ({
                        id,
                        question: index === 0 ? prompt.question : prompt.followUpQuestion,
                    })),
                }),
            ],
        }),
        listeners(({ actions, values, props, cache }) => ({
            schedulePrompt: ({ survey }) => {
                cache.matchingSurvey = survey
                if (
                    props.eligible === false ||
                    !props.userId ||
                    props.isImpersonated ||
                    values.visible ||
                    !survey ||
                    survey.type !== SurveyType.API ||
                    !survey.start_date ||
                    survey.end_date ||
                    !hasFeedbackQuestions(survey) ||
                    !posthog.is_capturing() ||
                    Date.now() - values.lastPromptAt < FEEDBACK_PROMPT_COOLDOWN_MS
                ) {
                    cache.disposables.dispose('prompt-delay')
                    cache.pendingSurvey = null
                    return
                }
                const alreadyPending =
                    cache.pendingSurvey?.id === survey.id && cache.disposables.registry.has('prompt-delay')
                cache.pendingSurvey = survey
                if (alreadyPending) {
                    return
                }
                const context = getContext()
                cache.disposables.add(() => {
                    const timer = window.setTimeout(() => {
                        if (getContext() !== context) {
                            return
                        }
                        const surveyToShow: Survey | null = cache.pendingSurvey
                        if (
                            surveyToShow &&
                            posthog.is_capturing() &&
                            Date.now() - values.lastPromptAt >= FEEDBACK_PROMPT_COOLDOWN_MS
                        ) {
                            actions.showPrompt(surveyToShow, Date.now(), crypto.randomUUID())
                        }
                        cache.pendingSurvey = null
                        cache.disposables.dispose('prompt-delay')
                    }, props.delayMs ?? FEEDBACK_PROMPT_DELAY_MS)
                    return () => window.clearTimeout(timer)
                }, 'prompt-delay')
            },
            recordImpression: () => {
                if (!values.visible || values.impressionRecorded || document.hidden || !posthog.is_capturing()) {
                    return
                }
                if (Date.now() - values.lastPromptAt < FEEDBACK_PROMPT_COOLDOWN_MS) {
                    actions.hidePrompt()
                    return
                }
                actions.impressionRecorded()
                actions.recordPrompt(Date.now())
                posthog.capture(SurveyEventName.SHOWN, values.surveyEventProperties)
            },
            recordPrompt: () => {
                if (!values.impressionRecorded) {
                    actions.hidePrompt()
                    cache.disposables.dispose('prompt-delay')
                }
            },
            dismissPrompt: () => {
                if (!values.visible) {
                    return
                }
                actions.recordImpression()
                if (values.impressionRecorded && values.survey && !values.completed) {
                    posthog.capture(SurveyEventName.DISMISSED, {
                        ...values.surveyEventProperties,
                        [SurveyEventProperties.SURVEY_PARTIALLY_COMPLETED]: !!values.answer,
                    })
                }
                actions.hidePrompt()
            },
            submitResponse: ({ answer, completed }) => {
                const { survey } = values
                const duplicateAnswer = !completed && !!values.answer
                const mismatchedCompletion = completed && (!values.answer || answer !== values.answer)
                if (
                    !values.visible ||
                    !survey ||
                    values.completed ||
                    values.submitting ||
                    duplicateAnswer ||
                    mismatchedCompletion ||
                    !hasFeedbackQuestions(survey) ||
                    (answer !== SURVEY_FEEDBACK_RATINGS.UP && answer !== SURVEY_FEEDBACK_RATINGS.DOWN)
                ) {
                    return
                }
                actions.recordImpression()
                if (!values.impressionRecorded) {
                    return
                }
                actions.captureStarted()
                try {
                    const queued = posthog.capture(SurveyEventName.SENT, {
                        ...values.surveyEventProperties,
                        [SurveyEventProperties.SURVEY_COMPLETED]: completed,
                        [`${SurveyEventProperties.SURVEY_RESPONSE}_${survey.questions[0].id}`]: answer,
                        ...(completed && values.detail.trim()
                            ? {
                                  [`${SurveyEventProperties.SURVEY_RESPONSE}_${survey.questions[1].id}`]:
                                      values.detail.trim(),
                              }
                            : {}),
                    })
                    if (queued) {
                        actions.responseQueued(answer, completed)
                    } else {
                        actions.responseFailed()
                    }
                } catch {
                    actions.responseFailed()
                }
            },
        })),
        propsChanged(({ actions, props, cache, values }, previousProps) => {
            if (props.eligible !== previousProps.eligible) {
                if (props.eligible === false && !values.impressionRecorded) {
                    actions.hidePrompt()
                }
                actions.schedulePrompt(cache.matchingSurvey ?? null)
            }
        }),
        afterMount(({ actions, cache, props }) => {
            const context = getContext()
            cache.disposables.add(() =>
                posthog.onSurveysLoaded((_, surveyContext) => {
                    if (surveyContext?.isLoaded) {
                        cache.disposables.add(
                            () =>
                                posthog.onFeatureFlags(() => {
                                    posthog.getActiveMatchingSurveys((surveys) => {
                                        if (!cache.disposables.isDisposed && getContext() === context) {
                                            actions.schedulePrompt(
                                                surveys.find(({ id }) => id === props.surveyId) ?? null
                                            )
                                        }
                                    })
                                }),
                            'survey-flags'
                        )
                    }
                })
            )
        }),
    ])
