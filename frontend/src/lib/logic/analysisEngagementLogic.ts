import { MakeLogicType, actions, kea, listeners, path, reducers } from 'kea'

import posthog from 'lib/posthog-typed'
import { sanitizeQuery } from 'lib/utils/eventUsageLogic'
import { objectClean } from 'lib/utils/objects'
import { userLogic } from 'scenes/userLogic'

import { Node } from '~/queries/schema/schema-general'

/** Which product surface rendered the result the user engaged with. */
export type AnalysisSurface = 'insight' | 'dashboard' | 'notebook' | 'sql_editor' | 'posthog_ai'

export interface AnalysisEngagement {
    /**
     * Identity of the thing analyzed. A saved object passes its short id, so returning to it during
     * one page visit counts once. An ad-hoc query passes a hash of the query itself, so each
     * distinct question a user asks counts separately.
     */
    key: string
    surface: AnalysisSurface
    query: Node | null
    insightShortId?: string | null
    dashboardId?: number | null
    isSaved?: boolean
    createdByUuid?: string | null
    /** Uninterrupted visible milliseconds that were required before this fired. */
    dwellMs: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analysisEngagementLogicValues {
    engagedKeys: string[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface analysisEngagementLogicActions {
    markEngaged: (key: string) => {
        key: string
    }
    reportAnalysisEngaged: (engagement: AnalysisEngagement) => {
        engagement: AnalysisEngagement
    }
}

export type analysisEngagementLogicType = MakeLogicType<analysisEngagementLogicValues, analysisEngagementLogicActions>

/**
 * Owns the `analysis engaged` event: a user held a rendered, non-empty analytical result in view
 * long enough to have read it.
 *
 * Callers decide when a result is worth counting; this logic decides whether it has been counted
 * already. Keys are held for the life of the page, so filter-fiddling on one saved insight counts
 * once while a reload starts a fresh count.
 */
export const analysisEngagementLogic = kea<analysisEngagementLogicType>([
    path(['lib', 'logic', 'analysisEngagementLogic']),
    actions({
        reportAnalysisEngaged: (engagement: AnalysisEngagement) => ({ engagement }),
        markEngaged: (key: string) => ({ key }),
    }),
    reducers({
        engagedKeys: [
            [] as string[],
            {
                markEngaged: (state, { key }) => (state.includes(key) ? state : [...state, key]),
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        reportAnalysisEngaged: ({ engagement }) => {
            if (values.engagedKeys.includes(engagement.key)) {
                return
            }
            actions.markEngaged(engagement.key)

            // Read through findMounted so this logic does not pull userLogic into every surface that
            // renders a result. The signed-in user is already loaded wherever a result can render.
            const viewerUuid = userLogic.findMounted()?.values.user?.uuid

            // pinned: analytics event name. This is the discoveries north-star metric, so renaming
            // it breaks the dashboards and insights built on it.
            posthog.capture(
                'analysis engaged',
                objectClean({
                    surface: engagement.surface,
                    insight_short_id: engagement.insightShortId ?? undefined,
                    dashboard_id: engagement.dashboardId ?? undefined,
                    is_saved: engagement.isSaved,
                    viewer_is_creator:
                        engagement.createdByUuid && viewerUuid ? engagement.createdByUuid === viewerUuid : undefined,
                    dwell_ms: engagement.dwellMs,
                    ...sanitizeQuery(engagement.query),
                    // Stamped so a future server-side emission for agent-driven analysis lands in the
                    // same breakdown. `source` is the property `posthog/event_usage.py` sets on
                    // product events.
                    source: 'web',
                })
            )
        },
    })),
])
