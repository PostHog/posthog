export const codeEditorLogic = kea<codeEditorLogicType>([
    path(['lib', 'monaco', 'hogQLMetadataProvider']),
    props({} as CodeEditorLogicProps),
    key((props) => props.key),
    actions({
        reloadMetadata: true,
        appendVimCommand: (command: string) => ({ command }),
    }),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),
    loaders(({ props, values }) => ({
        metadata: [
            null as null | [string, HogQLMetadataResponse],
            {
                reloadMetadata: async (_, breakpoint) => {
                    const model = props.editor?.getModel()
                    if (!model || !props.monaco || !METADATA_LANGUAGES.includes(props.language as HogLanguage)) {
                        props.onMetadata?.(null)
                        return null
                    }
                    await breakpoint(300)
                    const query = props.metadataQuery ?? props.query
                    if (query === '') {
                        props.onMetadata?.(null)
                        return null
                    }

                    const variables =
                        props.sourceQuery?.kind === NodeKind.HogQLQuery
                            ? (props.sourceQuery.variables ?? undefined)
                            : undefined
                    const connectionId =
                        props.sourceQuery?.kind === NodeKind.HogQLQuery
                            ? (props.sourceQuery.connectionId ?? undefined)
                            : undefined
                    const sourceQuery = getContextSourceQuery(props.sourceQuery, query)

                    const response = await performQuery<HogQLMetadata>(
                        setLatestVersionsOnQuery(
                            {
                                kind: NodeKind.HogQLMetadata,
                                language: props.language as HogLanguage,
                                query: query,
                                filters: props.metadataFilters,
                                globals: props.globals,
                                sourceQuery,
                                variables,
                                connectionId,
                                indexUsage: props.indexUsage,
                            },
                            { recursion: false }
                        )
                    )
                    breakpoint()

                    // The editor text can change while the request is in flight, for example when you
                    // open an insight into the editor. A response for text the editor no longer holds
                    // would give consumers errors and index usage for a statement nobody edits, so keep
                    // the last response that matched. The request for the new text publishes the
                    // correct metadata.
                    const currentModel = props.editor?.getModel()
                    if (!currentModel || !describesEditorText(currentModel, query, props.metadataQueryOffset ?? 0)) {
                        return values.metadata
                    }

                    props.onMetadata?.(response)
                    return [query, response]
                },
            },
        ],
        modelMarkers: [
            [] as ModelMarker[],
            {
                reloadMetadataSuccess: ({ metadata }) => {
                    const model = props.editor?.getModel()
                    if (!model || !metadata) {
                        return []
                    }
                    const markers: ModelMarker[] = []
                    const [query, metadataResponse] = metadata

                    const markerOffset = props.metadataQueryOffset ?? 0

                    // Markers from a response the editor text has moved past would land on unrelated
                    // characters, so keep the ones we have. The request for the new text paints the
                    // correct markers.
                    if (!describesEditorText(model, query, markerOffset)) {
                        return values.modelMarkers
                    }

                    // A notice can come back without a position. Do not stretch such a notice over the
                    // full statement, because that makes the whole editor red. Anchor it to the first
                    // character of the statement, and stop at the end of that line.
                    const firstCharacter = Math.max(query.search(/\S/), 0)

                    function noticeToMarker(error: HogQLNotice, severity: MarkerSeverity): ModelMarker {
                        const startOffset = error.start ?? firstCharacter
                        const lineEnd = query.indexOf('\n', startOffset)
                        const endOffset = error.end ?? (lineEnd === -1 ? query.length : lineEnd)
                        const start = model!.getPositionAt(startOffset + markerOffset)
                        const end = model!.getPositionAt(endOffset + markerOffset)
                        return {
                            start: startOffset,
                            startLineNumber: start.lineNumber,
                            startColumn: start.column,
                            end: endOffset,
                            endLineNumber: end.lineNumber,
                            endColumn: end.column,
                            message: error.message ?? 'Unknown error',
                            severity: severity,
                            hogQLFix: error.fix?.startsWith('ai_prompt:') ? undefined : error.fix,
                            hogQLAIFixPrompt: error.fix?.startsWith('ai_prompt:')
                                ? error.fix.slice('ai_prompt:'.length)
                                : undefined,
                        }
                    }

                    for (const notice of metadataResponse?.errors ?? []) {
                        markers.push(noticeToMarker(notice, 8 /* MarkerSeverity.Error */))
                    }
                    for (const notice of metadataResponse?.warnings ?? []) {
                        markers.push(noticeToMarker(notice, 4 /* MarkerSeverity.Warning */))
                    }
                    for (const notice of metadataResponse?.notices ?? []) {
                        markers.push(noticeToMarker(notice, 1 /* MarkerSeverity.Hint */))
                    }

                    props.monaco?.editor.setModelMarkers(model, 'hogql', markers)
                    return markers
                },
            },
        ],
    })),
    reducers({
        vimCommandHistory: [
            [] as string[],
            { persist: true, storageKey: 'posthog-vim-command-history' },
            {
                appendVimCommand: (state, { command }) => {
                    if (!command) {
                        return state
                    }
                    const deduped = state.filter((c) => c !== command)
                    return [...deduped, command].slice(-VIM_COMMAND_HISTORY_LIMIT)
                },
            },
        ],
    }),
    selectors({
        hasErrors: [
            (s) => [s.modelMarkers],
            (modelMarkers: ModelMarker[]) =>
                !!(modelMarkers ?? []).filter((e) => e.severity === 8 /* MarkerSeverity.Error */).length,
        ],
        error: [
            (s) => [s.hasErrors, s.modelMarkers],
            (hasErrors: boolean, modelMarkers: ModelMarker[]) => {
                const firstError = modelMarkers.find((e) => e.severity === 8 /* MarkerSeverity.Error */)
                return hasErrors && firstError
                    ? `Error on line ${firstError.startLineNumber}, column ${firstError.startColumn}`
                    : null
            },
        ],
    }),
    subscriptions(({ props }) => ({
        error: (error) => {
            props.onError?.(error)
        },
        metadataLoading: (loading) => {
            props.onMetadataLoading?.(loading)
        },
    })),
    propsChanged(({ actions, props }, oldProps) => {
        const previousConnectionId =
            oldProps.sourceQuery?.kind === NodeKind.HogQLQuery ? (oldProps.sourceQuery.connectionId ?? null) : null
        const nextConnectionId =
            props.sourceQuery?.kind === NodeKind.HogQLQuery ? (props.sourceQuery.connectionId ?? null) : null

        if (
            props.query !== oldProps.query ||
            props.metadataQuery !== oldProps.metadataQuery ||
            props.metadataQueryOffset !== oldProps.metadataQueryOffset ||
            props.language !== oldProps.language ||
            props.editor !== oldProps.editor ||
            nextConnectionId !== previousConnectionId
        ) {
            actions.reloadMetadata()
        }
    }),
])
