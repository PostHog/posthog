const METADATA_LANGUAGES = [HogLanguage.hog, HogLanguage.hogQL, HogLanguage.hogQLExpr, HogLanguage.hogTemplate]
const VIM_COMMAND_HISTORY_LIMIT = 50

/** True when the editor still holds `query` at `markerOffset`, so a response for it describes the text on screen. */
function describesEditorText(model: editor.ITextModel, query: string, markerOffset: number): boolean {
    return model.getValue().slice(markerOffset, markerOffset + query.length) === query
}

export interface ModelMarker extends editor.IMarkerData {
    hogQLFix?: string
    hogQLAIFixPrompt?: string
    start: number
    end: number
}

export interface CodeEditorLogicProps {
    key: string
    query: string
    metadataQuery?: string
    /** Character offset of metadataQuery within the full editor text, for correct marker positioning */
    metadataQueryOffset?: number
    language: string
    sourceQuery?: AnyDataNode
    metadataFilters?: HogQLFilters
    monaco?: Monaco | null
    editor?: editor.IStandaloneCodeEditor | null
    globals?: Record<string, any>
    onError?: (error: string | null) => void
    /** Ask for per-filter index eligibility. Costs a second resolution pass server-side, so set it only where the result is rendered. */
    indexUsage?: boolean
    onMetadata?: (metadata: HogQLMetadataResponse | null) => void
    onMetadataLoading?: (loading: boolean) => void
    onFixWithAI?: (prompt: string) => void
}

