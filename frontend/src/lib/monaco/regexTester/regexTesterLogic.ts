export const regexTesterLogic = kea<regexTesterLogicType>([
    path(['lib', 'monaco', 'regexTester', 'regexTesterLogic']),
    props({} as RegexTesterLogicProps),
    key((props) => props.logicKey),
    actions({
        openTester: (pattern: string) => ({ pattern }),
        closeTester: true,
        setTestString: (testString: string) => ({ testString }),
    }),
    reducers({
        pattern: [
            null as string | null,
            {
                openTester: (_, { pattern }) => pattern,
                closeTester: () => null,
            },
        ],
        // Deliberately survives close: hovering one pattern after another tests them all against
        // the same sample, which is how you compare two candidate patterns.
        testString: [
            '',
            {
                setTestString: (_, { testString }) => testString,
            },
        ],
    }),
    selectors({
        patternError: [
            (s) => [s.pattern],
            (pattern: string | null): string | null => (pattern ? compilePattern(pattern) : null),
        ],
        matches: [
            (s) => [s.pattern, s.testString],
            (pattern: string | null, testString: string): RegexTestMatch[] =>
                pattern ? findMatches(pattern, testString) : [],
        ],
    }),
])
