import { MakeLogicType, actions, kea, key, path, props, reducers, selectors } from 'kea'
import { RE2JS } from 're2js'

import { formatRE2Error } from 'lib/utils/regexp'

export interface RegexTestMatch {
    start: number
    end: number
    /** Capture groups 1..n, `null` where a group did not participate in the match. */
    groups: (string | null)[]
}

export interface RegexTesterLogicProps {
    /** Scopes the tester to one editor, so two editors on a page don't share a popover. */
    logicKey: string
}

/** A pattern like `a*` matches at every offset, so a long sample would otherwise build a huge list. */
const MAX_MATCHES = 200

/**
 * ClickHouse runs RE2, so the tester compiles with RE2 too. Its typings claim `start`/`end` return
 * strings; they return numbers.
 */
export function findMatches(pattern: string, value: string): RegexTestMatch[] {
    if (!pattern || !value) {
        return []
    }
    let matcher: ReturnType<RE2JS['matcher']>
    try {
        matcher = RE2JS.compile(pattern).matcher(value)
    } catch {
        return []
    }
    const matches: RegexTestMatch[] = []
    while (matches.length < MAX_MATCHES && matcher.find()) {
        const groups: (string | null)[] = []
        for (let group = 1; group <= matcher.groupCount(); group++) {
            // Typed as `string`, but a group that didn't participate comes back null.
            groups.push(matcher.group(group) as string | null)
        }
        matches.push({ start: Number(matcher.start()), end: Number(matcher.end()), groups })
    }
    return matches
}

export function compilePattern(pattern: string): string | null {
    try {
        RE2JS.compile(pattern)
        return null
    } catch (error) {
        return formatRE2Error(error as Error, pattern)
    }
}

