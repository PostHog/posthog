import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { lemonToast } from '@posthog/lemon-ui'

import { folderFormLogic } from 'lib/components/FileSystem/FolderSelect/folderFormLogic'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'

import { projectTreeDataLogic } from '~/layout/panel-layout/ProjectTree/projectTreeDataLogic'
import { PROJECT_TREE_KEY, projectTreeLogic } from '~/layout/panel-layout/ProjectTree/projectTreeLogic'
import { calculateMovePath } from '~/layout/panel-layout/ProjectTree/utils'
import { FileSystemEntry } from '~/queries/schema/schema-general'

import type { ProjectTreeRef } from '../../../../types'
import type { FeatureFlagsSet } from '../../../logic/featureFlagLogic'

/** Says why these items can't move into the folder right now, or null when they can. */
export type MoveToRefusal = (items: FileSystemEntry[], folder: string) => string | null

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface moveToLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    projectTreeRef: ProjectTreeRef | null // projectTreeDataLogic
    projectTreeRefEntry: FileSystemEntry | null // projectTreeDataLogic
    savedItems: FileSystemEntry[] // projectTreeDataLogic
    isOpen: boolean
    movingItems: FileSystemEntry[]
    refusal: MoveToRefusal | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface moveToLogicActions {
    startFrom: (items: FileSystemEntry[]) => {
        items: FileSystemEntry[]
    } // folderFormLogic
    moveItems: (
        moves: {
            item: FileSystemEntry
            newPath: string
        }[],
        force: boolean,
        projectTreeLogicKey: string
    ) => {
        force: boolean
        moves: {
            item: FileSystemEntry
            newPath: string
        }[]
        projectTreeLogicKey: string
    } // projectTreeDataLogic
    setLastNewFolder: (folder: string | null) => {
        folder: string | null
    } // projectTreeDataLogic
    closeMoveToModal: () => {
        value: true
    }
    closedMoveToModal: () => {
        value: true
    }
    openMoveToModal: (
        items: FileSystemEntry[],
        refusal?: MoveToRefusal
    ) => {
        items: FileSystemEntry[]
        refusal: MoveToRefusal | null
    }
}

export type moveToLogicType = MakeLogicType<moveToLogicValues, moveToLogicActions>

export const moveToLogic = kea<moveToLogicType>([
    path(['lib', 'components', 'MoveTo', 'moveToLogic']),
    connect(() => ({
        values: [
            projectTreeDataLogic,
            ['projectTreeRef', 'projectTreeRefEntry', 'savedItems'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [
            projectTreeDataLogic,
            ['setLastNewFolder', 'moveItems'],
            folderFormLogic({ dialog: 'move' }),
            ['startFrom'],
        ],
    })),
    actions({
        openMoveToModal: (items: FileSystemEntry[], refusal?: MoveToRefusal) => ({ items, refusal: refusal ?? null }),
        closeMoveToModal: true,
        closedMoveToModal: true,
    }),
    reducers({
        movingItems: [
            [] as FileSystemEntry[],
            {
                openMoveToModal: (_, { items }) => items,
                closeMoveToModal: () => [],
            },
        ],
        refusal: [
            null as MoveToRefusal | null,
            {
                openMoveToModal: (_, { refusal }) => refusal,
            },
        ],
        isOpen: [
            false,
            {
                openMoveToModal: (_, { items }) => items.length > 0,
                closedMoveToModal: () => false,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        openMoveToModal: ({ items }) => {
            actions.startFrom(items)
        },
        closeMoveToModal: () => {
            actions.closedMoveToModal()
        },
        [folderFormLogic({ dialog: 'move' }).actionTypes.submitFormSuccess]: ({ form }) => {
            // A folder can move while the dialog is open, so each item moves from where it is now. The index keeps
            // a large selection from scanning every saved item once per selected item.
            const savedById = new Map(values.savedItems.map((saved) => [saved.id, saved]))
            const movingItems = values.movingItems.map((item) => savedById.get(item.id) ?? item)
            const refusal = values.refusal?.(movingItems, form.folder || '')
            if (refusal) {
                lemonToast.error(refusal)
                return
            }
            // When moving the current item, remember its ref so that we could open the destination folder later on
            const movingCurrentRef =
                values.projectTreeRefEntry?.id && movingItems.some((item) => item.id === values.projectTreeRefEntry?.id)
                    ? values.projectTreeRef
                    : null
            // One batch for the whole selection, so it reports and undoes as a single move.
            const moves = movingItems
                .map((item) => ({ item, ...calculateMovePath(item, form.folder || '') }))
                .filter(({ isValidMove }) => isValidMove)
                .map(({ item, newPath }) => ({ item, newPath }))
            if (moves.length > 0) {
                actions.moveItems(moves, false, PROJECT_TREE_KEY)
            }

            // Clear the moving items and close the modal
            if (movingCurrentRef) {
                const logic = projectTreeLogic.findMounted({ key: PROJECT_TREE_KEY })
                logic?.actions.assureVisibility(movingCurrentRef)
            }

            actions.setLastNewFolder(form.folder)
            actions.closedMoveToModal()
        },
    })),
])
