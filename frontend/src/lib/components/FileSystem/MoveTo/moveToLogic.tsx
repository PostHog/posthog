export type moveToLogicType = MakeLogicType<moveToLogicValues, moveToLogicActions>

export const moveToLogic = kea<moveToLogicType>([
    path(['lib', 'components', 'MoveTo', 'moveToLogic']),
    connect(() => ({
        values: [
            projectTreeDataLogic,
            ['lastNewFolder', 'projectTreeRef', 'projectTreeRefEntry', 'savedItems'],
            featureFlagLogic,
            ['featureFlags'],
        ],
        actions: [projectTreeDataLogic, ['setLastNewFolder', 'moveItems']],
    })),
    actions({
        openMoveToModal: (items: FileSystemEntry[], refusal?: MoveToRefusal) => ({ items, refusal: refusal ?? null }),
        closeMoveToModal: true,
        closedMoveToModal: true,
    }),
    reducers({
        movingItems: [
            [] as FileSystemEntry[],
            {
                openMoveToModal: (_, { items }) => items,
                closeMoveToModal: () => [],
            },
        ],
        refusal: [
            null as MoveToRefusal | null,
            {
                openMoveToModal: (_, { refusal }) => refusal,
            },
        ],
        isOpen: [
            false,
            {
                openMoveToModal: (_, { items }) => items.length > 0,
                closedMoveToModal: () => false,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setLastNewFolder: ({ folder }) => {
            actions.setFormValue('folder', folder)
        },
        openMoveToModal: ({ items }) => {
            if (typeof values.lastNewFolder === 'string') {
                actions.setFormValue('folder', values.lastNewFolder)
            } else {
                const itemPath = items[0].path
                const itemFolder = parentPath(itemPath)
                actions.setFormValue('folder', itemFolder)
            }
        },
        closeMoveToModal: () => {
            actions.closedMoveToModal()
        },
    })),
    forms(({ actions, values }) => ({
        form: {
            defaults: {
                folder: null as string | null,
            },
            errors: ({ folder }) => ({
                folder: typeof folder !== 'string' ? 'You need to specify a folder.' : null,
            }),
            submit: (formValues) => {
                // A folder can move while the dialog is open, so each item moves from where it is now. The index keeps
                // a large selection from scanning every saved item once per selected item.
                const savedById = new Map(values.savedItems.map((saved) => [saved.id, saved]))
                const movingItems = values.movingItems.map((item) => savedById.get(item.id) ?? item)
                const refusal = values.refusal?.(movingItems, formValues.folder || '')
                if (refusal) {
                    lemonToast.error(refusal)
                    return
                }
                // When moving the current item, remember its ref so that we could open the destination folder later on
                const movingCurrentRef =
                    values.projectTreeRefEntry?.id &&
                    movingItems.some((item) => item.id === values.projectTreeRefEntry?.id)
                        ? values.projectTreeRef
                        : null
                // One batch for the whole selection, so it reports and undoes as a single move.
                const moves = movingItems
                    .map((item) => ({ item, ...calculateMovePath(item, formValues.folder || '') }))
                    .filter(({ isValidMove }) => isValidMove)
                    .map(({ item, newPath }) => ({ item, newPath }))
                if (moves.length > 0) {
                    actions.moveItems(moves, false, PROJECT_TREE_KEY)
                }

                // Clear the moving items and close the modal
                if (movingCurrentRef) {
                    const logic = projectTreeLogic.findMounted({ key: PROJECT_TREE_KEY })
                    logic?.actions.assureVisibility(movingCurrentRef)
                }

                actions.setLastNewFolder(formValues.folder)
                actions.closedMoveToModal()
            },
        },
    })),
])
