// Resolving a selection sends one request per ref, so chunk them rather than firing a burst of up to a
// full page of parallel requests when a list page moves everything the user selected.
const REF_RESOLUTION_BATCH_SIZE = 10

// The sidebar's in-memory store only holds the folders it has lazily loaded, so callers that know an object
// only by its ref have to ask the file system for its row. Shortcuts share a ref with the row they point at,
// and moving one would move the shortcut instead of the object, so skip them.
async function resolveRef({ type, ref }: ProjectTreeRef): Promise<FileSystemEntry | null> {
    if (!ref) {
        return null
    }
    try {
        const response = await api.fileSystem.list({ type, ref, limit: 10 })
        return response.results.find((entry) => !entry.shortcut) ?? null
    } catch (error) {
        // Runs in an async listener rather than a kea-loader, so initKea's global onFailure never sees it.
        posthog.captureException(error)
        return null
    }
}

