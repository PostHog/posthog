import { MakeLogicType, actions, connect, kea, listeners, path, reducers } from 'kea'

import { folderFormLogic } from 'lib/components/FileSystem/FolderSelect/folderFormLogic'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'

import { projectTreeDataLogic } from '~/layout/panel-layout/ProjectTree/projectTreeDataLogic'
import { PROJECT_TREE_KEY, projectTreeLogic } from '~/layout/panel-layout/ProjectTree/projectTreeLogic'
import { calculateMovePath } from '~/layout/panel-layout/ProjectTree/utils'
import { FileSystemEntry } from '~/queries/schema/schema-general'

import type { ProjectTreeRef } from '../../../../types'
import type { FeatureFlagsSet } from '../../../logic/featureFlagLogic'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface linkToLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    projectTreeRef: ProjectTreeRef | null // projectTreeDataLogic
    projectTreeRefEntry: FileSystemEntry | null // projectTreeDataLogic
    isOpen: boolean
    linkingItems: FileSystemEntry[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface linkToLogicActions {
    startFrom: (items: FileSystemEntry[]) => {
        items: FileSystemEntry[]
    } // folderFormLogic
    linkItem: (
        oldPath: string,
        newPath: string,
        force: boolean,
        projectTreeLogicKey: string
    ) => {
        force: boolean
        newPath: string
        oldPath: string
        projectTreeLogicKey: string
    } // projectTreeDataLogic
    setLastNewFolder: (folder: string | null) => {
        folder: string | null
    } // projectTreeDataLogic
    closeLinkToModal: () => {
        value: true
    }
    closedLinkToModal: () => {
        value: true
    }
    openLinkToModal: (items: FileSystemEntry[]) => {
        items: FileSystemEntry[]
    }
}

export type linkToLogicType = MakeLogicType<linkToLogicValues, linkToLogicActions>

export const linkToLogic = kea<linkToLogicType>([
    path(['lib', 'components', 'LinkTo', 'linkToLogic']),
    connect(() => ({
        values: [projectTreeDataLogic, ['projectTreeRef', 'projectTreeRefEntry'], featureFlagLogic, ['featureFlags']],
        actions: [
            projectTreeDataLogic,
            ['setLastNewFolder', 'linkItem'],
            folderFormLogic({ dialog: 'link' }),
            ['startFrom'],
        ],
    })),
    actions({
        openLinkToModal: (items: FileSystemEntry[]) => ({ items }),
        closeLinkToModal: true,
        closedLinkToModal: true,
    }),
    reducers({
        linkingItems: [
            [] as FileSystemEntry[],
            {
                openLinkToModal: (_, { items }) => items,
                closeLinkToModal: () => [],
            },
        ],
        isOpen: [
            false,
            {
                openLinkToModal: (_, { items }) => items.length > 0,
                closedLinkToModal: () => false,
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        openLinkToModal: ({ items }) => {
            actions.startFrom(items)
        },
        closeLinkToModal: () => {
            actions.closedLinkToModal()
        },
        [folderFormLogic({ dialog: 'link' }).actionTypes.submitFormSuccess]: ({ form }) => {
            // When moving the current item, remember its ref so that we could open the destination folder later on
            const movingCurrentRef =
                values.projectTreeRefEntry?.id &&
                values.linkingItems.some((item) => item.id === values.projectTreeRefEntry?.id)
                    ? values.projectTreeRef
                    : null

            if (values.linkingItems.length > 0) {
                for (const item of values.linkingItems) {
                    const { newPath, isValidMove } = calculateMovePath(item, form.folder || '')
                    if (isValidMove) {
                        actions.linkItem(item.path, newPath, false, PROJECT_TREE_KEY)
                    }
                }
            }

            // Clear the moving items and close the modal
            if (movingCurrentRef) {
                const logic = projectTreeLogic.findMounted({ key: PROJECT_TREE_KEY })
                logic?.actions.assureVisibility(movingCurrentRef)
            }

            actions.setLastNewFolder(form.folder)
            actions.closedLinkToModal()
        },
    })),
])
