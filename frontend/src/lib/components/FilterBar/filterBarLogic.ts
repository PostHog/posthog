export type FilterBarStage = 'fields' | 'values' | 'save'

interface ItemsState {
    nextId: number
    items: FilterBarItem[]
}

function initItems(filters: AnyPropertyFilter[]): ItemsState {
    return { nextId: filters.length, items: filters.map((filter, id) => ({ id, filter })) }
}

function fieldFromDefinition(
    categoryId: FilterBarCategoryId,
    definition: { name: string; property_type?: string | null; description?: string | null }
): FilterBarField {
    return {
        categoryId,
        key: definition.name,
        label: fieldLabelForKey(categoryId, definition.name),
        propertyType: (definition.property_type as PropertyType) || null,
        description: definition.description ?? null,
    }
}

function fieldFromCohort(cohort: CohortType): FilterBarField {
    return { categoryId: 'cohorts', key: String(cohort.id), label: cohort.name || `Cohort ${cohort.id}` }
}

function matchesQuery(text: string, query: string): boolean {
    return text.toLowerCase().includes(query.trim().toLowerCase())
}

