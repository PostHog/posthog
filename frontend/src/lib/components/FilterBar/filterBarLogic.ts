interface FilterBarCommonProps {
    /** Scopes the logic to one surface, so two bars on a page keep separate pickers. */
    pageKey: string
    /** The categories the bar offers. Defaults to every category that does not need opting in. */
    categoryIds?: FilterBarCategoryId[]
}

interface FilterBarFlatProps {
    filters: AnyPropertyFilter[]
    onChange: (filters: AnyPropertyFilter[]) => void
    filterGroup?: undefined
    onFilterGroupChange?: undefined
}

/** For a surface that stores AND/OR groups. It lets people build OR branches, and it can opt in to `events`. */
interface FilterBarGroupProps {
    filterGroup: UniversalFiltersGroup
    onFilterGroupChange: (group: UniversalFiltersGroup) => void
    filters?: undefined
    onChange?: undefined
}

export type FilterBarLogicProps = FilterBarCommonProps & (FilterBarFlatProps | FilterBarGroupProps)

export type FilterBarStage = 'fields' | 'category' | 'values' | 'save'

function valueFromProps(props: FilterBarLogicProps): FilterBarValue {
    return props.filterGroup ?? props.filters ?? []
}

function fieldFromDefinition(
    categoryId: FilterBarCategoryId,
    definition: { name: string; property_type?: string | null; description?: string | null }
): FilterBarField {
    return {
        categoryId,
        key: definition.name,
        label: fieldLabelForKey(categoryId, definition.name),
        propertyType: (definition.property_type as PropertyType) || null,
        description: definition.description ?? null,
    }
}

function fieldFromCohort(cohort: CohortType): FilterBarField {
    return { categoryId: 'cohorts', key: String(cohort.id), label: cohort.name || `Cohort ${cohort.id}` }
}

function matchesQuery(text: string, query: string): boolean {
    return text.toLowerCase().includes(query.trim().toLowerCase())
}

