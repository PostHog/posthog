export const HERTS_WILDLIFE_TRUST_DONATE_URL = 'https://www.hertswildlifetrust.org.uk/donate'

// We ask at most twice a year, so a donation window is six months long.
const WINDOW_MONTHS = 6

// A team is "under the free allowance" when it's on the free plan and no product has spilled past
// its free allocation. The backend computes this authoritatively (`is_under_free_allowance`); we
// fall back to the same check client-side when the field is absent (e.g. unlicensed / hobby).
// The billing payload only describes the *current* period, so "for the past six months" is
// approximated by combining this with the donation window below.
export function isUnderFreeAllowance(billing: BillingType | null): boolean {
    if (!billing) {
        return false
    }
    if (billing.is_under_free_allowance !== undefined) {
        return billing.is_under_free_allowance
    }
    if (billing.has_active_subscription || billing.subscription_level !== 'free') {
        return false
    }
    return (billing.products ?? []).every(
        (product) =>
            !product.has_exceeded_limit &&
            (product.free_allocation == null || (product.current_usage ?? 0) <= product.free_allocation)
    )
}

/**
 * Which six-month donation window the org is in, counted from its own creation date, or null when
 * it hasn't reached the first one yet (so this doubles as the "long-term free user" gate).
 *
 * Anchoring to the org's birthday rather than the calendar keeps every window exactly six months
 * long. Keying off calendar halves instead would show the card again days after someone dismissed
 * it, whenever they first became eligible near a boundary.
 */
export function donationWindowIndex(orgCreatedAt: string | undefined, now: Dayjs): number | null {
    if (!orgCreatedAt) {
        return null
    }
    const index = Math.floor(now.diff(dayjs(orgCreatedAt), 'month') / WINDOW_MONTHS)
    // Window 0 is the org's first six months - too new to count as a long-term free user.
    return index >= 1 ? index : null
}

/** Dismissal is persisted against this, so a new window (or a different org) shows the card again. */
export function donationCampaignKey(orgId: string, windowIndex: number): string {
    return `hedgehog-coffee-${orgId}-w${windowIndex}`
}

