export const facetSearchBarLogic = kea<facetSearchBarLogicType>([
    props({} as FacetSearchBarLogicProps),
    key((props) => props.id),
    path((key) => ['lib', 'components', 'FacetSearchBar', 'facetSearchBarLogic', key]),
    actions({
        setInput: (input: string) => ({ input }),
        syncInput: (input: string) => ({ input }),
        setOpen: (open: boolean) => ({ open }),
        setHighlightedIndex: (index: number) => ({ index }),
        moveHighlight: (delta: number) => ({ delta }),
        applySuggestion: (suggestion: FacetSuggestion) => ({ suggestion }),
        applyHighlighted: true,
        applyTabTarget: true,
        removeFilter: (filter: FacetFilter) => ({ filter }),
        removeLastFilter: true,
        loadValues: true,
        setValuesState: (loadKey: string, state: FacetValuesState) => ({ loadKey, state }),
        forgetValues: (facetKeys: string[]) => ({ facetKeys }),
        propsUpdated: true,
    }),
    reducers(({ props }) => ({
        input: [
            props.value.text,
            {
                setInput: (_, { input }) => input,
                syncInput: (_, { input }) => input,
            },
        ],
        open: [
            false,
            {
                setOpen: (_, { open }) => open,
                setInput: () => true,
            },
        ],
        typedSinceOpen: [
            false,
            {
                setInput: () => true,
                setOpen: () => false,
            },
        ],
        rawHighlightedIndex: [
            0,
            {
                setHighlightedIndex: (_, { index }) => index,
                setInput: () => 0,
                syncInput: () => 0,
                setOpen: () => 0,
            },
        ],
        valueLoads: [
            {} as FacetValueLoads,
            {
                setValuesState: (loads, { loadKey, state }) => ({ ...loads, [loadKey]: state }),
                forgetValues: (loads, { facetKeys }) => forgetValuesOf(loads, facetKeys),
            },
        ],
        // Kea updates props in place, so selectors that read props also read this to see a new render.
        propsRevision: [
            0,
            {
                propsUpdated: (revision) => revision + 1,
            },
        ],
    })),
    selectors({
        draft: [
            (s, p) => [s.input, p.facets, s.propsRevision],
            (input: string, facets: AnyFacet[]): FacetDraft | null => parseFacetDraft(input, facets),
        ],
        suggestions: [
            (s, p) => [s.input, s.draft, p.facets, p.data, p.value, s.valueLoads, s.propsRevision],
            (
                input: string,
                draft: FacetDraft | null,
                facets: AnyFacet[],
                data: FacetSearchBarLogicProps['data'],
                value: FacetSearchValue,
                valueLoads: FacetValueLoads
            ): FacetSuggestion[] =>
                buildSuggestions(input, draft, { facets, data, filters: value.filters, valueLoads }),
        ],
        failedLabelFacets: [
            (s, p) => [p.facets, s.valueLoads, s.propsRevision],
            (facets: AnyFacet[], valueLoads: FacetValueLoads): Set<string> =>
                facetsWithFailedLabels(facets, valueLoads),
        ],
        valueLabels: [
            (s, p) => [p.facets, s.valueLoads, s.propsRevision],
            (facets: AnyFacet[], valueLoads: FacetValueLoads): FacetValueLabels =>
                labelsByFilterValue(facets, valueLoads),
        ],
        pendingValueRequests: [
            (s, p) => [s.input, s.draft, s.open, p.facets, p.value, s.valueLabels, s.valueLoads, s.propsRevision],
            (
                input: string,
                draft: FacetDraft | null,
                open: boolean,
                facets: AnyFacet[],
                value: FacetSearchValue,
                valueLabels: FacetValueLabels,
                valueLoads: FacetValueLoads
            ): FacetValueRequest[] =>
                pendingValueRequests({ input, draft, open, facets, filters: value.filters, valueLabels, valueLoads }),
        ],
        options: [
            (s) => [s.suggestions],
            (suggestions: FacetSuggestion[]): FacetSuggestion[] =>
                suggestions.filter((suggestion) => suggestion.kind !== 'message'),
        ],
        statusMessage: [
            (s) => [s.suggestions],
            (suggestions: FacetSuggestion[]): string | null =>
                suggestions.find((suggestion) => suggestion.kind === 'message')?.label ?? null,
        ],
        highlightedIndex: [
            (s) => [s.rawHighlightedIndex, s.options],
            (raw: number, options: FacetSuggestion[]): number => Math.max(0, Math.min(raw, options.length - 1)),
        ],
        highlightedSuggestion: [
            (s) => [s.options, s.highlightedIndex],
            (options: FacetSuggestion[], index: number): FacetSuggestion | null => options[index] ?? null,
        ],
        tabTarget: [
            (s) => [s.input, s.typedSinceOpen, s.options, s.highlightedSuggestion],
            (
                input: string,
                typedSinceOpen: boolean,
                options: FacetSuggestion[],
                highlighted: FacetSuggestion | null
            ): FacetSuggestion | null => {
                // Tab and → never run a plain search. Until the person types, Tab moves focus as usual.
                if (!input.trim() || !typedSinceOpen) {
                    return null
                }
                return isFilterRow(highlighted) ? highlighted : (options.find(isFilterRow) ?? null)
            },
        ],
        title: [
            (s, p) => [s.input, s.draft, p.facets, s.propsRevision],
            (input: string, draft: FacetDraft | null, facets: AnyFacet[]): string => {
                if (draft) {
                    const label = findFacet(facets, draft.facetKey)?.label ?? draft.facetKey
                    return `${label}${draft.negated ? ' is not' : ''}`
                }
                return input.trim() ? 'Search or filter' : 'Filter by'
            },
        ],
        hints: [
            (s) => [s.highlightedSuggestion, s.tabTarget],
            (highlighted: FacetSuggestion | null, tabTarget: FacetSuggestion | null): KeyHint[] => {
                const hints: KeyHint[] = []
                if (highlighted?.kind === 'search') {
                    hints.push({ keys: ['enter'], action: 'to search' })
                } else if (highlighted && isFilterRow(highlighted)) {
                    const keys: HotKeyOrModifier[] = tabTarget === highlighted ? ['enter', 'tab'] : ['enter']
                    hints.push({ keys, action: `to ${verbOf(highlighted)}` })
                }
                if (tabTarget && tabTarget !== highlighted) {
                    hints.push({ keys: ['tab', 'arrowright'], action: `to ${verbOf(tabTarget)}` })
                }
                if (highlighted) {
                    hints.push({ keys: ['arrowup', 'arrowdown'], action: 'to navigate' })
                }
                return [...hints, { keys: ['escape'], action: 'to close' }]
            },
        ],
    }),
    listeners(({ actions, values, props, cache }) => {
        const emit = (value: FacetSearchValue): void => {
            cache.lastEmitted = searchKey(value)
            props.onChange(value)
        }
        const loadPendingValues = (): void => {
            if (values.pendingValueRequests.length) {
                actions.loadValues()
            }
        }
        const loadUnstartedValues = (): void => {
            const unstarted = ({ facet, search }: FacetValueRequest): boolean =>
                !values.valueLoads[valueLoadKey(facet.key, search)]
            if (values.pendingValueRequests.some(unstarted)) {
                actions.loadValues()
            }
        }
        const newestLoadByKey = new Map<string, symbol>()
        // A bar mounted later with the same key shares this logic's actions, so a finished load must check its own bar.
        const isStillCurrent = ({ facet }: FacetValueRequest, loadKey: string, load: symbol): boolean => {
            const current = findFacet(props.facets, facet.key)
            return (
                !cache.unmounted &&
                newestLoadByKey.get(loadKey) === load &&
                !!current &&
                isLoadedFacet(current) &&
                current.loadValues === facet.loadValues
            )
        }
        const runValueRequest = async (request: FacetValueRequest): Promise<void> => {
            const loadKey = valueLoadKey(request.facet.key, request.search)
            const load = Symbol(loadKey)
            newestLoadByKey.set(loadKey, load)
            actions.setValuesState(loadKey, { status: 'loading' })
            let state: FacetValuesState
            try {
                const options = await request.facet.loadValues(request.search.trim())
                state = { status: 'loaded', options: uniqBy(options, 'value') }
            } catch (error) {
                state = { status: 'error', reason: error instanceof Error ? error.message : undefined }
            }
            if (isStillCurrent(request, loadKey, load)) {
                actions.setValuesState(loadKey, state)
            }
        }

        return {
            setInput: ({ input }) => {
                // Typed or pasted `facet:value` tokens become pills as soon as they are complete.
                const { filters, remaining } = extractFacetFilters(input, props.facets, { untilEnd: false })
                const nextFilters = uniqBy([...props.value.filters, ...filters], pillIdentity(props.data))
                const nextInput = filters.length ? remaining : input
                const text = textOf(nextInput, parseFacetDraft(nextInput, props.facets))
                if (filters.length) {
                    actions.syncInput(nextInput)
                }
                if (nextFilters.length > props.value.filters.length || text !== props.value.text) {
                    emit({ filters: nextFilters, text })
                }
                loadPendingValues()
            },
            setOpen: ({ open }) => {
                if (open) {
                    loadPendingValues()
                }
            },
            // A failed load runs again only when the person types or reopens the bar, not on each render of the consumer.
            propsUpdated: loadUnstartedValues,
            loadValues: async (_, breakpoint) => {
                await breakpoint(VALUE_LOAD_DEBOUNCE_MS)
                await Promise.all(values.pendingValueRequests.map(runValueRequest))
            },
            forgetValues: ({ facetKeys }) => {
                for (const loadKey of newestLoadByKey.keys()) {
                    if (facetKeys.some((facetKey) => loadKey.startsWith(`${facetKey}:`))) {
                        newestLoadByKey.delete(loadKey)
                    }
                }
            },
            moveHighlight: ({ delta }) => {
                const last = Math.max(0, values.options.length - 1)
                actions.setHighlightedIndex(Math.max(0, Math.min(values.highlightedIndex + delta, last)))
            },
            applySuggestion: ({ suggestion }) => {
                if (suggestion.kind === 'facet' && suggestion.nextInput !== undefined) {
                    actions.setInput(suggestion.nextInput)
                } else if (suggestion.kind === 'value' && suggestion.filter) {
                    const rest = (suggestion.rest ?? '').trimEnd()
                    emit({ filters: [...props.value.filters, suggestion.filter], text: rest.trim() })
                    actions.syncInput(rest ? `${rest} ` : '')
                    actions.setOpen(true)
                } else {
                    actions.setOpen(false)
                }
            },
            applyHighlighted: () => {
                if (values.highlightedSuggestion) {
                    actions.applySuggestion(values.highlightedSuggestion)
                }
            },
            applyTabTarget: () => {
                if (values.tabTarget) {
                    actions.applySuggestion(values.tabTarget)
                }
            },
            removeFilter: ({ filter }) => {
                const removed = facetFilterKey(filter)
                emit({
                    filters: props.value.filters.filter((f) => facetFilterKey(f) !== removed),
                    text: props.value.text,
                })
            },
            removeLastFilter: () => {
                if (props.value.filters.length) {
                    emit({ filters: props.value.filters.slice(0, -1), text: props.value.text })
                }
            },
        }
    }),
    afterMount(({ actions, values }) => {
        if (values.pendingValueRequests.length) {
            actions.loadValues()
        }
    }),
    beforeUnmount(({ cache }) => {
        cache.unmounted = true
    }),
    propsChanged(({ actions, values, props, cache }, oldProps) => {
        const replacedLoaders = facetsWithNewLoaders(oldProps.facets, props.facets)
        if (replacedLoaders.length) {
            actions.forgetValues(replacedLoaders)
        }
        // The URL or a "Clear filters" button can change the search without this input. That drops a typed draft too.
        const changedOutside =
            searchKey(props.value) !== searchKey(oldProps.value) && searchKey(props.value) !== cache.lastEmitted
        if (changedOutside || !sameText(props.value.text, textOf(values.input, values.draft))) {
            actions.syncInput(props.value.text)
        }
        if (props.facets !== oldProps.facets || props.data !== oldProps.data || props.value !== oldProps.value) {
            actions.propsUpdated()
        }
    }),
])
