export const flagCalledRebuildBannerLogic = kea<flagCalledRebuildBannerLogicType>([
    path(['lib', 'components', 'FlagCalledRebuildBanner', 'flagCalledRebuildBannerLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentProjectId'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        reportBannerShown: (artifactType: FlagCalledArtifactType) => ({ artifactType }),
        loadReferencedActions: (actionIds: number[]) => ({ actionIds }),
        addReferencedActions: (referencedActions: ActionApi[]) => ({ referencedActions }),
    }),
    reducers({
        // Each fetch merges into the state, so overlapping fetches cannot drop each other's actions.
        // A refetched action replaces its old copy.
        referencedActions: [
            [] as ActionApi[],
            {
                addReferencedActions: (state, { referencedActions }) => {
                    const fetchedIds = new Set(referencedActions.map((action) => action.id))
                    return [...state.filter((action) => !fetchedIds.has(action.id)), ...referencedActions]
                },
            },
        ],
    }),
    selectors({
        // A team on mode 0 still builds events series in its pickers, so it has no way to rebuild yet.
        bannersEnabled: [
            (s) => [s.currentTeam, s.featureFlags],
            (currentTeam: TeamPublicType | TeamType | null, featureFlags: FeatureFlagsSet): boolean =>
                !!featureFlags[FEATURE_FLAGS.FLAG_CALLED_MOVE_NOTICES] && readsFlagEvaluationsTable(currentTeam),
        ],
        // Reads the payload when the flags change, because the payload arrives with them.
        announcementUrl: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): string | null =>
                featureFlags[FEATURE_FLAGS.FLAG_CALLED_MOVE_NOTICES]
                    ? announcementUrlFromPayload(getFeatureFlagPayload(FEATURE_FLAGS.FLAG_CALLED_MOVE_NOTICES))
                    : null,
        ],
    }),
    listeners(({ actions, values }) => ({
        // Fetches only the actions a banner references. The full actions list can hold thousands of actions.
        // Insight and dashboard view modes do not load it.
        loadReferencedActions: async ({ actionIds }) => {
            const results = await Promise.allSettled(
                actionIds.map((id) => actionsRetrieve(String(values.currentProjectId), id))
            )
            // An action that fails to load counts as not reading the event, so its banner stays hidden.
            actions.addReferencedActions(
                results.flatMap((result) => (result.status === 'fulfilled' ? [result.value] : []))
            )
        },
        reportBannerShown: ({ artifactType }) => {
            // pinned: analytics event name and property. Renaming them breaks the insights that count banner views.
            posthog.capture('flag called rebuild banner shown', { artifact_type: artifactType })
        },
    })),
])
