import { MakeLogicType, actions, connect, kea, listeners, path, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { FEATURE_FLAGS } from 'lib/constants'
import { FeatureFlagsSet, featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { readsFlagEvaluationsTable } from 'scenes/feature-flags/featureFlagUsageQueries'
import { teamLogic } from 'scenes/teamLogic'

import { TeamPublicType, TeamType } from '~/types'

import { actionsRetrieve } from 'products/actions/frontend/generated/api'
import type { ActionApi } from 'products/actions/frontend/generated/api.schemas'

export type FlagCalledArtifactType = 'insight' | 'dashboard' | 'action' | 'cohort' | 'experiment'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface flagCalledRebuildBannerLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    currentProjectId: number | string // teamLogic
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    bannersEnabled: boolean
    referencedActions: ActionApi[]
    referencedActionsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface flagCalledRebuildBannerLogicActions {
    loadReferencedActions: (actionIds: number[]) => number[]
    loadReferencedActionsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadReferencedActionsSuccess: (
        referencedActions: ActionApi[],
        payload?: number[]
    ) => {
        referencedActions: ActionApi[]
        payload?: number[]
    }
    reportBannerShown: (artifactType: FlagCalledArtifactType) => {
        artifactType: FlagCalledArtifactType
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface flagCalledRebuildBannerLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        bannersEnabled: (currentTeam: TeamPublicType | TeamType | null, featureFlags: FeatureFlagsSet) => boolean
    }
}

export type flagCalledRebuildBannerLogicType = MakeLogicType<
    flagCalledRebuildBannerLogicValues,
    flagCalledRebuildBannerLogicActions,
    Record<string, any>,
    flagCalledRebuildBannerLogicMeta
>

export const flagCalledRebuildBannerLogic = kea<flagCalledRebuildBannerLogicType>([
    path(['lib', 'components', 'FlagCalledRebuildBanner', 'flagCalledRebuildBannerLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeam', 'currentProjectId'], featureFlagLogic, ['featureFlags']],
    })),
    actions({
        reportBannerShown: (artifactType: FlagCalledArtifactType) => ({ artifactType }),
    }),
    loaders(({ values }) => ({
        // Fetches only the actions a banner references. The full actions list can hold thousands of actions.
        // Insight and dashboard view modes do not load it.
        referencedActions: [
            [] as ActionApi[],
            {
                loadReferencedActions: async (actionIds: number[]) => {
                    const loadedIds = new Set(values.referencedActions.map((action) => action.id))
                    const missingIds = [...new Set(actionIds)].filter((id) => !loadedIds.has(id))
                    if (!missingIds.length) {
                        return values.referencedActions
                    }
                    const results = await Promise.allSettled(
                        missingIds.map((id) => actionsRetrieve(String(values.currentProjectId), id))
                    )
                    // A deleted action no longer matches events, so a failed fetch leaves it out.
                    return [
                        ...values.referencedActions,
                        ...results.flatMap((result) => (result.status === 'fulfilled' ? [result.value] : [])),
                    ]
                },
            },
        ],
    })),
    selectors({
        // A team on mode 0 still builds events series in its pickers, so it has no way to rebuild yet.
        bannersEnabled: [
            (s) => [s.currentTeam, s.featureFlags],
            (currentTeam: TeamPublicType | TeamType | null, featureFlags: FeatureFlagsSet): boolean =>
                !!featureFlags[FEATURE_FLAGS.FLAG_CALLED_REBUILD_BANNERS] && readsFlagEvaluationsTable(currentTeam),
        ],
    }),
    listeners({
        reportBannerShown: ({ artifactType }) => {
            // pinned: analytics event name and property. Renaming them breaks the insights that count banner views.
            posthog.capture('flag called rebuild banner shown', { artifact_type: artifactType })
        },
    }),
])
