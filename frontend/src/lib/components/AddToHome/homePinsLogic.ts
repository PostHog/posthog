import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import { toast } from '@posthog/quill'

import { ApiError } from 'lib/api'
import { teamLogic } from 'scenes/teamLogic'

import { isInsightVizNode, isTrendsQuery } from '~/queries/schema/node-guards'
import { ChartDisplayType, type InsightModel } from '~/types'

import { todayPulsePinsRetrieve, todayPulsePinsUpdate } from 'products/today/frontend/generated/api'
import type { PulsePinApi } from 'products/today/frontend/generated/api.schemas'

export const HOME_PIN_LIMIT = 4

const HOME_PIN_DISPLAYS: ChartDisplayType[] = [
    ChartDisplayType.ActionsLineGraph,
    ChartDisplayType.ActionsBar,
    ChartDisplayType.ActionsStackedBar,
    ChartDisplayType.ActionsAreaGraph,
]

export type HomePinSource = 'dashboard_card' | 'insight_menu'

export type HomePinInsight = Pick<InsightModel, 'short_id'> & Partial<Pick<InsightModel, 'name' | 'derived_name'>>

export interface HomePinState {
    pinned: boolean
    disabledReason: string | undefined
}

export function isHomePinnable(insight: Partial<InsightModel>): insight is Partial<InsightModel> & HomePinInsight {
    const query = insight.query
    return (
        !!insight.short_id &&
        isInsightVizNode(query) &&
        isTrendsQuery(query.source) &&
        HOME_PIN_DISPLAYS.includes(query.source.trendsFilter?.display ?? ChartDisplayType.ActionsLineGraph)
    )
}

function homePinKey(insight: HomePinInsight): string {
    return `insight:${insight.short_id}`
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface homePinsLogicValues {
    currentProjectId: number | null
    homePinState: (insight: HomePinInsight) => HomePinState
    homePins: PulsePinApi[] | null
    homePinsLoading: boolean
    homePinsSaving: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface homePinsLogicActions {
    loadHomePins: () => any
    loadHomePinsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadHomePinsSuccess: (
        homePins: PulsePinApi[] | null,
        payload?: any
    ) => {
        homePins: PulsePinApi[] | null
        payload?: any
    }
    setHomePinsSaving: (saving: boolean) => {
        saving: boolean
    }
    toggleHomePin: (
        insight: HomePinInsight,
        source: HomePinSource
    ) => {
        insight: HomePinInsight
        source: HomePinSource
    }
}

export type homePinsLogicType = MakeLogicType<homePinsLogicValues, homePinsLogicActions>

function nextHomePins(pins: PulsePinApi[], insight: HomePinInsight, pinned: boolean): PulsePinApi[] {
    const key = homePinKey(insight)
    if (pinned) {
        return pins.filter((pin) => pin.key !== key)
    }
    return [...pins, { key, name: insight.name || insight.derived_name || 'Untitled insight', dashboard_id: null }]
}

export const homePinsLogic = kea<homePinsLogicType>([
    path(['lib', 'components', 'AddToHome', 'homePinsLogic']),
    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),
    actions({
        toggleHomePin: (insight: HomePinInsight, source: HomePinSource) => ({ insight, source }),
        setHomePinsSaving: (saving: boolean) => ({ saving }),
    }),
    loaders(({ values }) => ({
        homePins: [
            null as PulsePinApi[] | null,
            {
                loadHomePins: async (): Promise<PulsePinApi[] | null> => {
                    try {
                        const { pins } = await todayPulsePinsRetrieve(String(values.currentProjectId))
                        return pins
                    } catch (error) {
                        if (error instanceof ApiError && error.status === 404) {
                            return []
                        }
                        throw error
                    }
                },
            },
        ],
    })),
    reducers({
        homePinsSaving: [false, { setHomePinsSaving: (_, { saving }) => saving }],
    }),
    selectors({
        homePinState: [
            (s) => [s.homePins, s.homePinsLoading, s.homePinsSaving],
            (homePins: PulsePinApi[] | null, homePinsLoading: boolean, homePinsSaving: boolean) =>
                (insight: HomePinInsight): HomePinState => {
                    const pinned = !!homePins?.some((pin) => pin.key === homePinKey(insight))
                    const disabledReason =
                        homePinsLoading || homePinsSaving
                            ? 'Loading your home numbers'
                            : homePins === null
                              ? "Couldn't load your home numbers. Open this menu again to retry."
                              : !pinned && homePins.length >= HOME_PIN_LIMIT
                                ? `Your home already shows ${HOME_PIN_LIMIT} numbers. Remove one first.`
                                : undefined
                    return { pinned, disabledReason }
                },
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        toggleHomePin: async ({ insight, source }) => {
            const pins = values.homePins
            const { pinned, disabledReason } = values.homePinState(insight)
            if (!pins || disabledReason) {
                return
            }
            const next = nextHomePins(pins, insight, pinned)
            actions.setHomePinsSaving(true)
            let saved: PulsePinApi[]
            try {
                saved = (await todayPulsePinsUpdate(String(values.currentProjectId), { pins: next })).pins
            } catch {
                toast.error({ title: "Couldn't update your home. Try again." })
                if (!cache.disposables.isDisposed) {
                    actions.setHomePinsSaving(false)
                }
                return
            }
            posthog.capture(pinned ? 'today pulse number unpinned' : 'today pulse number pinned', {
                kind: 'insight',
                source,
                pinned_count_before: pins.length,
            })
            toast.success({ title: pinned ? 'Removed from home' : 'Added to home' })
            if (!cache.disposables.isDisposed) {
                actions.loadHomePinsSuccess(saved)
                actions.setHomePinsSaving(false)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadHomePins()
    }),
])
