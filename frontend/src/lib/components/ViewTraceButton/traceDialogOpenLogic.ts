/**
 * Whether the trace dialog is open, and which trace it shows. Every logged-in page mounts this logic,
 * so it must not import feature code. traceDialogLogic loads the trace when the dialog mounts.
 */
export const traceDialogOpenLogic = kea<traceDialogOpenLogicType>([
    path(['lib', 'components', 'ViewTraceButton', 'traceDialogOpenLogic']),
    connect(() => ({
        actions: [router, ['locationChanged']],
        values: [featureFlagLogic, ['featureFlags']],
    })),
    actions({
        openTraceDialog: (trace: TraceLinkParams, options: OpenTraceDialogOptions) => ({
            trace: { ...trace, spanId: inApiCase(trace.spanId) },
            openedFrom: options.openedFrom ?? null,
            entryPoint: options.entryPoint,
        }),
        closeTraceDialog: (reason: TraceDialogCloseReason = 'dismissed') => ({ reason }),
    }),
    reducers({
        isOpen: [
            false,
            {
                openTraceDialog: () => true,
                closeTraceDialog: () => false,
            },
        ],
        // Survives close: useKeepMountedWhileOpen keeps the dialog rendered through its exit
        // animation, and clearing the trace then would flash an empty dialog.
        trace: [
            null as TraceLinkParams | null,
            {
                openTraceDialog: (_, { trace }) => trace,
            },
        ],
        openedFrom: [
            null as TraceDialogSource | null,
            {
                openTraceDialog: (_, { openedFrom }) => openedFrom,
            },
        ],
        entryPoint: [
            null as TraceDialogEntryPoint | null,
            {
                openTraceDialog: (_, { entryPoint }) => entryPoint,
            },
        ],
    }),
    selectors({
        // Every entry point checks this one place, so the flag cannot open the dialog from some
        // links and not others.
        dialogEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TRACING_TRACE_DIALOG],
        ],
    }),
    listeners(({ values, actions, cache }) => ({
        locationChanged: ({ pathname }) => {
            // Query and hash changes fire locationChanged too, so only a new pathname closes the dialog.
            if (pathname === cache.lastPathname) {
                return
            }
            cache.lastPathname = pathname
            if (values.isOpen) {
                actions.closeTraceDialog('navigated')
            }
        },
    })),
    afterMount(({ cache }) => {
        cache.lastPathname = router.values.location.pathname
    }),
])
