/** The log the dialog was opened from, shown above the tree so the reason for the trace stays in view. */
export interface TraceDialogSource {
    body: string
    severity: LogSeverityLevel
}

/** Where a trace dialog was opened from. Sent with every dialog event, so keep the values stable. */
export type TraceDialogEntryPoint =
    | 'log_details'
    | 'log_expanded_row'
    | 'log_row_action'
    | 'log_trace_id_cell'
    | 'metric_sample'
    | 'metric_exemplar'

export type TraceDialogCloseReason = 'dismissed' | 'back_to_log' | 'open_in_tracing' | 'navigated' | 'replaced'

export interface OpenTraceDialogOptions {
    entryPoint: TraceDialogEntryPoint
    openedFrom?: TraceDialogSource | null
}

// The trace API returns hex span ids in uppercase, and logs and metrics carry them in lowercase. The
// dialog matches the opened span against the loaded spans exactly, so it keeps the API's case.
function inApiCase(spanId: string | null | undefined): string | null {
    if (!spanId) {
        return null
    }
    return usableId(spanId) ? spanId.toUpperCase() : spanId
}

