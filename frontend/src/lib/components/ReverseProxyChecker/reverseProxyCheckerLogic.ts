import { MakeLogicType, afterMount, kea, listeners, path } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { ApiError } from 'lib/api-error'
import { SetupTaskId, globalSetupLogic } from 'lib/components/ProductSetup'
import { getCurrentTeamIdOrNone } from 'lib/utils/getAppContext'
import { sceneLogic } from 'scenes/sceneLogic'

import { hogql } from '~/queries/utils'

const CHECK_INTERVAL_MS = 1000 * 60 * 10 // 10 minutes
const LAST_CHECK_STORAGE_KEY = 'ph-reverse-proxy-check-last-run'

// The throttle lives in localStorage, not per-mount state, so a page reload no longer re-fires the
// advisory query. Keyed by team because the check reads the current team's events.
function lastCheckedAt(teamId: number | null): number {
    if (teamId == null) {
        return 0
    }
    try {
        const raw = localStorage.getItem(`${LAST_CHECK_STORAGE_KEY}-${teamId}`)
        return raw ? Number(raw) : 0
    } catch {
        return 0
    }
}

function markChecked(teamId: number | null): void {
    if (teamId == null) {
        return
    }
    try {
        localStorage.setItem(`${LAST_CHECK_STORAGE_KEY}-${teamId}`, String(Date.now()))
    } catch {
        // localStorage can be unavailable (private mode, disabled). Losing the throttle only means
        // the advisory check may run again, which is harmless.
    }
}

// The check is advisory and falls back safely, so a failed run needs no user action and points to no
// frontend fix. Its failures are transient and outside a frontend fix: network blips, 5xx and
// timeouts from the query service, and "... is not known" guards thrown while the team still loads.
// Capturing them splinters error tracking into one issue per environment id and status code, so skip
// the capture for them and keep it for anything genuinely unexpected.
function isExpectedCheckFailure(error: unknown): boolean {
    if (error instanceof ApiError) {
        // A status-less ApiError is a failed fetch that never reached the server (offline, reset,
        // ad-blocker); a 5xx or a 408/504 timeout is a server-side problem a frontend cannot fix.
        return error.status === undefined || error.status >= 500 || error.status === 408
    }
    if (error instanceof TypeError) {
        return true // raw `fetch` failure, e.g. "Failed to fetch"
    }
    const message = error instanceof Error ? error.message : ''
    return message.includes('is not known.')
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reverseProxyCheckerLogicValues {
    hasReverseProxy: boolean | null
    hasReverseProxyLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reverseProxyCheckerLogicActions {
    loadHasReverseProxy: () => any
    loadHasReverseProxyFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadHasReverseProxySuccess: (
        hasReverseProxy: boolean | null,
        payload?: any
    ) => {
        hasReverseProxy: boolean | null
        payload?: any
    }
}

export type reverseProxyCheckerLogicType = MakeLogicType<
    reverseProxyCheckerLogicValues,
    reverseProxyCheckerLogicActions
>

export const reverseProxyCheckerLogic = kea<reverseProxyCheckerLogicType>([
    path(['components', 'ReverseProxyChecker', 'reverseProxyCheckerLogic']),
    loaders(({ values }) => ({
        hasReverseProxy: [
            // null until the detection query resolves — consumers must distinguish "not yet
            // checked" from a confirmed `false` so they don't act before the result is in.
            null as boolean | null,
            {
                loadHasReverseProxy: async () => {
                    const teamId = getCurrentTeamIdOrNone()
                    if (lastCheckedAt(teamId) > Date.now() - CHECK_INTERVAL_MS) {
                        return values.hasReverseProxy
                    }

                    markChecked(teamId)

                    // We only need to know whether any matching event exists, so stop at the first
                    // row instead of running a DISTINCT scan — that keeps the check cheap and stops
                    // it timing out on large projects.
                    const query = hogql`
                        SELECT properties.$lib_custom_api_host AS lib_custom_api_host
                        FROM events
                        WHERE timestamp >= now() - INTERVAL 1 DAY
                        AND timestamp <= now()
                        AND properties.$lib_custom_api_host IS NOT NULL
                        AND event IN ('$pageview', '$screen')
                        LIMIT 1`

                    const currentScene = sceneLogic.findMounted()?.values.activeSceneId ?? 'Onboarding'
                    try {
                        const res = await api.queryHogQL(query, {
                            scene: currentScene,
                            productKey: 'platform_and_support',
                        })
                        return !!res.results?.find((x) => !!x[0])
                    } catch (error) {
                        // This check is advisory (used only to auto-complete a setup task).
                        // Swallow errors so kea-loaders does not surface a user-visible toast
                        // on every scene that mounts ProductSetupButton.
                        //
                        // Capturing the original `error` directly (rather than wrapping it
                        // in `new Error('...', { cause })`) keeps the error type at the top
                        // of `$exception_list`, so the central `before_send` filter in
                        // `selfReadOnlyModeLogic` can drop `ReadOnlyModeError` without
                        // assuming posthog-js serialises the cause chain.
                        if (!isExpectedCheckFailure(error)) {
                            posthog.captureException(error, {
                                posthog_source: 'reverseProxyCheckerLogic.loadHasReverseProxy',
                            })
                        }
                        return values.hasReverseProxy
                    }
                },
            },
        ],
    })),
    listeners(({ values }) => ({
        loadHasReverseProxySuccess: () => {
            if (values.hasReverseProxy) {
                globalSetupLogic.findMounted()?.actions.markTaskAsCompleted(SetupTaskId.SetUpReverseProxy)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadHasReverseProxy()
    }),
])
