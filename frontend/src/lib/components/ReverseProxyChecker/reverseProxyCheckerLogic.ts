import { MakeLogicType, afterMount, kea, listeners, path } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { ApiError, TRANSIENT_GATEWAY_STATUSES } from 'lib/api-error'
import { SetupTaskId, globalSetupLogic } from 'lib/components/ProductSetup'
import { sceneLogic } from 'scenes/sceneLogic'

import { hogql } from '~/queries/utils'

const CHECK_INTERVAL_MS = 1000 * 60 * 10 // 10 minutes

// Network hiccups that say nothing about the user's setup: the tab closed mid-request,
// connectivity dropped, an extension cut the request, or a gateway answered 502/503/504. Each
// carries a content-hashed bundle name in its stack, so every deploy re-fingerprints the same
// failure as first-seen. A 500 is a genuine backend exception and stays reported. Exported for
// testing.
export function isTransientNetworkError(error: unknown): boolean {
    // A gateway/proxy hiccup carries a 5xx status; the api layer wraps a dropped `fetch` in a
    // statusless ApiError, so those fall through to the message check below.
    if (error instanceof ApiError && error.status !== undefined) {
        return TRANSIENT_GATEWAY_STATUSES.includes(error.status)
    }
    // A raw `fetch` rejection reads differently per browser — Chrome "Failed to fetch", Safari
    // "Load failed", Firefox "NetworkError when attempting to fetch resource" — and reaches here
    // either bare or as the message of a statusless ApiError.
    const message = error instanceof Error ? error.message : String(error ?? '')
    return /failed to fetch|load failed|networkerror when attempting to fetch/i.test(message)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reverseProxyCheckerLogicValues {
    hasReverseProxy: boolean | null
    hasReverseProxyLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface reverseProxyCheckerLogicActions {
    loadHasReverseProxy: () => any
    loadHasReverseProxyFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadHasReverseProxySuccess: (
        hasReverseProxy: boolean | null,
        payload?: any
    ) => {
        hasReverseProxy: boolean | null
        payload?: any
    }
}

export type reverseProxyCheckerLogicType = MakeLogicType<
    reverseProxyCheckerLogicValues,
    reverseProxyCheckerLogicActions
>

export const reverseProxyCheckerLogic = kea<reverseProxyCheckerLogicType>([
    path(['components', 'ReverseProxyChecker', 'reverseProxyCheckerLogic']),
    loaders(({ values, cache }) => ({
        hasReverseProxy: [
            // null until the detection query resolves — consumers must distinguish "not yet
            // checked" from a confirmed `false` so they don't act before the result is in.
            null as boolean | null,
            {
                loadHasReverseProxy: async () => {
                    if (cache.lastCheckedTimestamp > Date.now() - CHECK_INTERVAL_MS) {
                        return values.hasReverseProxy
                    }

                    cache.lastCheckedTimestamp = Date.now()

                    const query = hogql`
                        SELECT DISTINCT properties.$lib_custom_api_host AS lib_custom_api_host
                        FROM events
                        WHERE timestamp >= now() - INTERVAL 1 DAY
                        AND timestamp <= now()
                        AND properties.$lib_custom_api_host IS NOT NULL
                        AND event IN ('$pageview', '$screen')
                        LIMIT 10`

                    const currentScene = sceneLogic.findMounted()?.values.activeSceneId ?? 'Onboarding'
                    try {
                        const res = await api.queryHogQL(query, {
                            scene: currentScene,
                            productKey: 'platform_and_support',
                        })
                        return !!res.results?.find((x) => !!x[0])
                    } catch (error) {
                        // This check is advisory (used only to auto-complete a setup task).
                        // Swallow errors so kea-loaders does not surface a user-visible toast
                        // on every scene that mounts ProductSetupButton.
                        //
                        // Report only genuinely unexpected errors. Benign network noise has no
                        // user impact here, yet each deploy re-fingerprints it as a fresh error
                        // tracking issue, so capturing it only drowns real regressions in triage.
                        //
                        // Capturing the original `error` directly (rather than wrapping it
                        // in `new Error('...', { cause })`) keeps the error type at the top
                        // of `$exception_list`, so the central `before_send` filter in
                        // `selfReadOnlyModeLogic` can drop `ReadOnlyModeError` without
                        // assuming posthog-js serialises the cause chain.
                        if (!isTransientNetworkError(error)) {
                            posthog.captureException(error, {
                                posthog_source: 'reverseProxyCheckerLogic.loadHasReverseProxy',
                            })
                        }
                        return values.hasReverseProxy
                    }
                },
            },
        ],
    })),
    listeners(({ values }) => ({
        loadHasReverseProxySuccess: () => {
            if (values.hasReverseProxy) {
                globalSetupLogic.findMounted()?.actions.markTaskAsCompleted(SetupTaskId.SetUpReverseProxy)
            }
        },
    })),
    afterMount(({ actions }) => {
        actions.loadHasReverseProxy()
    }),
])
