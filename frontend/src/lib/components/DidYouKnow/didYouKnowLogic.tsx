import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers } from 'kea'
import posthog from 'posthog-js'
import { toast } from 'react-toastify'

import { IconX } from '@posthog/icons'

import { LemonButton } from 'lib/lemon-ui/LemonButton'
import { featureFlagLogic } from 'lib/logic/featureFlagLogic'
import { isHttpsUrl } from 'lib/utils/url'

import type { FeatureFlagsSet } from '../../logic/featureFlagLogic'
import { DidYouKnowTipKey, didYouKnowFlagKey } from './didYouKnowTips'
import type { DidYouKnowAction, DidYouKnowPayload } from './DidYouKnowToast'

const AUTO_DISMISS_MS = process.env.NODE_ENV === 'development' ? false : 15000
const COOLDOWN_MS = 7 * 24 * 60 * 60 * 1000

function parseAction(value: unknown): DidYouKnowAction | undefined {
    if (!value || typeof value !== 'object' || Array.isArray(value)) {
        return undefined
    }

    const { label, url } = value as Record<string, unknown>
    if (typeof label !== 'string' || typeof url !== 'string') {
        return undefined
    }

    const trimmedLabel = label.trim()
    const trimmedUrl = url.trim()
    const isSafeUrl = isHttpsUrl(trimmedUrl) || (trimmedUrl.startsWith('/') && !trimmedUrl.startsWith('//'))

    return trimmedLabel && isSafeUrl ? { label: trimmedLabel, url: trimmedUrl } : undefined
}

export function parseDidYouKnowPayload(value: unknown): DidYouKnowPayload | null {
    if (!value || typeof value !== 'object' || Array.isArray(value)) {
        return null
    }

    const { title, description, action } = value as Record<string, unknown>
    if (typeof description !== 'string' || !description.trim()) {
        return null
    }

    return {
        title: typeof title === 'string' && title.trim() ? title.trim() : 'Did you know?',
        description: description.trim(),
        action: parseAction(action),
    }
}

// Attempts made before the host logic mounts (e.g. a direct page load) are replayed once it does.
const pendingTips = new Set<DidYouKnowTipKey>()

export function tryShowDidYouKnow(tipKey: DidYouKnowTipKey): void {
    try {
        const mounted = didYouKnowLogic.findMounted()
        if (mounted) {
            mounted.actions.tryShowTip(tipKey)
        } else {
            pendingTips.add(tipKey)
        }
    } catch (error) {
        console.warn('[didYouKnow] dispatch failed', { tipKey, error })
    }
}

export function markDidYouKnowTipAsMastered(tipKey: DidYouKnowTipKey): void {
    try {
        const mounted = didYouKnowLogic.findMounted()
        if (!mounted || mounted.values.masteredTips[tipKey]) {
            return
        }
        mounted.actions.markTipAsMastered(tipKey)
    } catch (error) {
        console.warn('[didYouKnow] mastery dispatch failed', { tipKey, error })
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface didYouKnowLogicValues {
    featureFlags: FeatureFlagsSet // featureFlagLogic
    dismissedTips: Partial<Record<DidYouKnowTipKey, true>>
    lastShownAt: number | null
    masteredTips: Partial<Record<DidYouKnowTipKey, true>>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface didYouKnowLogicActions {
    dismissTip: (tipKey: DidYouKnowTipKey) => {
        tipKey: 'sql-editor-shortcut'
    }
    markTipAsMastered: (tipKey: DidYouKnowTipKey) => {
        tipKey: 'sql-editor-shortcut'
    }
    recordActionClicked: (tipKey: DidYouKnowTipKey) => {
        tipKey: 'sql-editor-shortcut'
    }
    recordShown: (now: number) => {
        now: number
    }
    reportTipShown: (tipKey: DidYouKnowTipKey) => {
        tipKey: 'sql-editor-shortcut'
    }
    tryShowTip: (tipKey: DidYouKnowTipKey) => {
        tipKey: 'sql-editor-shortcut'
    }
}

export type didYouKnowLogicType = MakeLogicType<didYouKnowLogicValues, didYouKnowLogicActions>

export const didYouKnowLogic = kea<didYouKnowLogicType>([
    path(['lib', 'components', 'DidYouKnow', 'didYouKnowLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags']],
    })),
    actions({
        tryShowTip: (tipKey: DidYouKnowTipKey) => ({ tipKey }),
        recordShown: (now: number) => ({ now }),
        reportTipShown: (tipKey: DidYouKnowTipKey) => ({ tipKey }),
        dismissTip: (tipKey: DidYouKnowTipKey) => ({ tipKey }),
        markTipAsMastered: (tipKey: DidYouKnowTipKey) => ({ tipKey }),
        recordActionClicked: (tipKey: DidYouKnowTipKey) => ({ tipKey }),
    }),
    reducers({
        lastShownAt: [
            null as number | null,
            { persist: true },
            {
                recordShown: (_, { now }) => now,
            },
        ],
        dismissedTips: [
            {} as Partial<Record<DidYouKnowTipKey, true>>,
            { persist: true },
            {
                dismissTip: (state, { tipKey }) => ({ ...state, [tipKey]: true }),
            },
        ],
        masteredTips: [
            {} as Partial<Record<DidYouKnowTipKey, true>>,
            { persist: true },
            {
                markTipAsMastered: (state, { tipKey }) => ({ ...state, [tipKey]: true }),
            },
        ],
    }),
    listeners(({ values, actions, cache }) => ({
        tryShowTip: async ({ tipKey }) => {
            if (cache.loadingTip) {
                return
            }
            const now = Date.now()
            const cooldownActive = values.lastShownAt !== null && now - values.lastShownAt < COOLDOWN_MS
            if (values.dismissedTips[tipKey] || values.masteredTips[tipKey] || cooldownActive) {
                return
            }

            const flagKey = didYouKnowFlagKey(tipKey)
            const flagValue = (values.featureFlags as Record<string, boolean | string | undefined>)[flagKey]
            if (flagValue !== true) {
                return
            }

            const payload = parseDidYouKnowPayload(
                posthog.getFeatureFlagResult(flagKey, { send_event: false })?.payload
            )
            if (!payload) {
                return
            }

            cache.loadingTip = true
            try {
                // Load first so a failed chunk doesn't burn the cooldown for a tip nobody saw
                const { DidYouKnowToast } = await import('./DidYouKnowToast')
                actions.recordShown(now)
                const toastId = `did-you-know-${tipKey}-${now}`
                toast.info(
                    <DidYouKnowToast
                        payload={payload}
                        onActionClick={payload.action ? () => actions.recordActionClicked(tipKey) : undefined}
                    />,
                    {
                        toastId,
                        autoClose: AUTO_DISMISS_MS,
                        closeOnClick: false,
                        draggable: false,
                        hideProgressBar: true,
                        icon: false,
                        closeButton: ({ closeToast }) => (
                            <LemonButton
                                type="tertiary"
                                size="small"
                                icon={<IconX />}
                                tooltip="Dismiss"
                                onClick={(event) => {
                                    closeToast(event)
                                    actions.dismissTip(tipKey)
                                }}
                                data-attr="did-you-know-dismiss"
                            />
                        ),
                    }
                )
                actions.reportTipShown(tipKey)
            } catch (error) {
                console.warn('[didYouKnow] toast render failed', { tipKey, error })
            } finally {
                cache.loadingTip = false
            }
        },
        // pinned: analytics event names and properties
        reportTipShown: ({ tipKey }) => {
            posthog.capture('did you know shown', { tip_key: tipKey })
        },
        dismissTip: ({ tipKey }) => {
            posthog.capture('did you know dismissed', { tip_key: tipKey })
        },
        markTipAsMastered: ({ tipKey }) => {
            posthog.capture('did you know mastered', { tip_key: tipKey })
        },
        recordActionClicked: ({ tipKey }) => {
            posthog.capture('did you know action clicked', { tip_key: tipKey })
        },
    })),
    afterMount(({ actions }) => {
        const tips = [...pendingTips]
        pendingTips.clear()
        tips.forEach((tipKey) => actions.tryShowTip(tipKey))
    }),
])
