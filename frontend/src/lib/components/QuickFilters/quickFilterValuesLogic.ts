import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
    selectors,
} from 'kea'

import { projectLogic } from 'scenes/projectLogic'

import { eventsValuesRetrieve } from '~/generated/core/api'
import type { EventPropertyValueApi } from '~/generated/core/api.schemas'
import { QuickFilterContext } from '~/queries/schema/schema-general'
import { QuickFilterOption } from '~/types'

import { QUICK_FILTER_VALUE_EVENT_NAMES } from './consts'
import { autoDiscoveredOption } from './quickFilterOptions'

const SEARCH_DEBOUNCE_MS = 200

export type DiscoveredValuesStatus = 'loading' | 'loaded' | 'error'

export interface QuickFilterValuesLogicProps {
    context: QuickFilterContext
    propertyName: string
}

function toValueNames(results: EventPropertyValueApi[]): string[] {
    const names = results.map((result) => (result.name === null ? '' : String(result.name)))
    return Array.from(new Set(names.filter((name) => name !== '')))
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface quickFilterValuesLogicValues {
    currentProjectId: number | null // projectLogic
    discoveredOptions: QuickFilterOption[]
    discoveredValuesStatus: DiscoveredValuesStatus
    failedSearch: string | null
    search: string
    valuesBySearch: Record<string, string[]>
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface quickFilterValuesLogicActions {
    loadValues: (search: string) => {
        search: string
    }
    setSearch: (search: string) => {
        search: string
    }
    setValues: (
        search: string,
        values: string[]
    ) => {
        search: string
        values: string[]
    }
    setValuesFailed: (search: string) => {
        search: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface quickFilterValuesLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        discoveredOptions: (search: string, valuesBySearch: Record<string, string[]>) => QuickFilterOption[]
        discoveredValuesStatus: (
            search: string,
            valuesBySearch: Record<string, string[]>,
            failedSearch: string | null
        ) => DiscoveredValuesStatus
    }
}

export type quickFilterValuesLogicType = MakeLogicType<
    quickFilterValuesLogicValues,
    quickFilterValuesLogicActions,
    QuickFilterValuesLogicProps,
    quickFilterValuesLogicMeta
>

export const quickFilterValuesLogic: LogicWrapper<quickFilterValuesLogicType> = kea<quickFilterValuesLogicType>([
    props({} as QuickFilterValuesLogicProps),
    key((props) => `${props.context}-${props.propertyName}`),
    path((key) => ['lib', 'components', 'QuickFilters', 'quickFilterValuesLogic', key]),

    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),

    actions({
        setSearch: (search: string) => ({ search }),
        loadValues: (search: string) => ({ search }),
        setValues: (search: string, values: string[]) => ({ search, values }),
        setValuesFailed: (search: string) => ({ search }),
    }),

    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        valuesBySearch: [
            {} as Record<string, string[]>,
            { setValues: (state, { search, values }) => ({ ...state, [search]: values }) },
        ],
        // Failures are not cached, so opening the dropdown again retries the request.
        failedSearch: [null as string | null, { loadValues: () => null, setValuesFailed: (_, { search }) => search }],
    }),

    selectors({
        discoveredOptions: [
            (s) => [s.search, s.valuesBySearch],
            (search: string, valuesBySearch: Record<string, string[]>): QuickFilterOption[] => {
                if (Object.hasOwn(valuesBySearch, search)) {
                    return valuesBySearch[search].map(autoDiscoveredOption)
                }
                // Until the server answers a search, narrow the unfiltered values so the list reacts to typing at once
                const lowerSearch = search.toLowerCase()
                return (valuesBySearch[''] ?? [])
                    .filter((value) => value.toLowerCase().includes(lowerSearch))
                    .map(autoDiscoveredOption)
            },
        ],
        discoveredValuesStatus: [
            (s) => [s.search, s.valuesBySearch, s.failedSearch],
            (
                search: string,
                valuesBySearch: Record<string, string[]>,
                failedSearch: string | null
            ): DiscoveredValuesStatus => {
                if (Object.hasOwn(valuesBySearch, search)) {
                    return 'loaded'
                }
                return search === failedSearch ? 'error' : 'loading'
            },
        ],
    }),

    listeners(({ actions, values, props, cache }) => ({
        setSearch: async ({ search }, breakpoint) => {
            if (Object.hasOwn(values.valuesBySearch, search)) {
                return
            }
            if (search) {
                await breakpoint(SEARCH_DEBOUNCE_MS)
            }
            actions.loadValues(search)
        },
        loadValues: async ({ search }) => {
            cache.pendingSearches ??= new Set<string>()
            if (cache.pendingSearches.has(search) || !values.currentProjectId) {
                return
            }
            cache.pendingSearches.add(search)
            try {
                const response = await eventsValuesRetrieve(String(values.currentProjectId), {
                    key: props.propertyName,
                    event_name: QUICK_FILTER_VALUE_EVENT_NAMES[props.context],
                    ...(search ? { value: search } : {}),
                })
                if (!cache.disposables.isDisposed) {
                    actions.setValues(search, toValueNames(response.results))
                }
            } catch {
                if (!cache.disposables.isDisposed) {
                    actions.setValuesFailed(search)
                }
            } finally {
                cache.pendingSearches.delete(search)
            }
        },
    })),

    // Load before the dropdown opens, so the values are ready when the user clicks
    afterMount(({ actions }) => {
        actions.loadValues('')
    }),
])
