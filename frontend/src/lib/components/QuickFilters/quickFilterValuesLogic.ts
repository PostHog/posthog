import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    connect,
    kea,
    key,
    listeners,
    path,
    props,
    reducers,
    selectors,
} from 'kea'

import { projectLogic } from 'scenes/projectLogic'

import { eventsValuesRetrieve } from '~/generated/core/api'
import type { EventPropertyValueApi } from '~/generated/core/api.schemas'
import { QuickFilterContext } from '~/queries/schema/schema-general'
import { QuickFilterOption } from '~/types'

import { QUICK_FILTER_VALUE_EVENT_NAMES } from './consts'
import { autoDiscoveredOption } from './quickFilterOptions'

const SEARCH_DEBOUNCE_MS = 200
// New values keep arriving while a scene stays open, so opening the dropdown refreshes values older than this
const STALE_AFTER_MS = 5 * 60 * 1000

export type DiscoveredValuesStatus = 'loading' | 'loaded' | 'error'

/** The status line for a discovered-values dropdown, or null when the values need no explanation. */
export function discoveredValuesMessage(
    status: DiscoveredValuesStatus,
    search: string,
    valueCount: number
): string | null {
    if (status === 'loading') {
        return 'Loading values…'
    }
    if (status === 'error') {
        return "Couldn't load values. Close and reopen the dropdown to try again."
    }
    if (valueCount > 0) {
        return null
    }
    return search ? 'No matching values in the last 7 days.' : 'No values found in the last 7 days.'
}

export interface QuickFilterValuesLogicProps {
    context: QuickFilterContext
    propertyName: string
}

function toValueNames(results: EventPropertyValueApi[]): string[] {
    const names = results.map((result) => String(result.name))
    return Array.from(new Set(names.filter((name) => name !== '')))
}

