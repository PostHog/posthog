export const quickFilterValuesLogic: LogicWrapper<quickFilterValuesLogicType> = kea<quickFilterValuesLogicType>([
    props({} as QuickFilterValuesLogicProps),
    key((props) => `${props.context}-${props.propertyName}`),
    path((key) => ['lib', 'components', 'QuickFilters', 'quickFilterValuesLogic', key]),

    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
        actions: [projectLogic, ['loadCurrentProjectSuccess']],
    })),

    actions({
        setSearch: (search: string) => ({ search }),
        loadValues: (search: string) => ({ search }),
        setValues: (search: string, values: string[], fetchedAt: number = Date.now()) => ({
            search,
            values,
            fetchedAt,
        }),
        setValuesFailed: (search: string) => ({ search }),
    }),

    reducers({
        search: ['', { setSearch: (_, { search }) => search }],
        valuesBySearch: [
            {} as Record<string, string[]>,
            { setValues: (state, { search, values }) => ({ ...state, [search]: values }) },
        ],
        fetchedAtBySearch: [
            {} as Record<string, number>,
            { setValues: (state, { search, fetchedAt }) => ({ ...state, [search]: fetchedAt }) },
        ],
        // Failures are not cached, so opening the dropdown again retries the request.
        failedSearch: [null as string | null, { loadValues: () => null, setValuesFailed: (_, { search }) => search }],
    }),

    selectors({
        discoveredOptions: [
            (s) => [s.search, s.valuesBySearch],
            (search: string, valuesBySearch: Record<string, string[]>): QuickFilterOption[] => {
                if (Object.hasOwn(valuesBySearch, search)) {
                    return valuesBySearch[search].map(autoDiscoveredOption)
                }
                // Until the server answers a search, narrow the unfiltered values so the list reacts to typing at once
                const lowerSearch = search.toLowerCase()
                return (valuesBySearch[''] ?? [])
                    .filter((value) => value.toLowerCase().includes(lowerSearch))
                    .map(autoDiscoveredOption)
            },
        ],
        discoveredValuesStatus: [
            (s) => [s.search, s.valuesBySearch, s.failedSearch],
            (
                search: string,
                valuesBySearch: Record<string, string[]>,
                failedSearch: string | null
            ): DiscoveredValuesStatus => {
                if (Object.hasOwn(valuesBySearch, search)) {
                    return 'loaded'
                }
                return search === failedSearch ? 'error' : 'loading'
            },
        ],
    }),

    listeners(({ actions, values, props, cache }) => ({
        setSearch: async ({ search }, breakpoint) => {
            const fetchedAt = values.fetchedAtBySearch[search]
            if (fetchedAt !== undefined && Date.now() - fetchedAt < STALE_AFTER_MS) {
                return
            }
            if (search) {
                await breakpoint(SEARCH_DEBOUNCE_MS)
            }
            actions.loadValues(search)
        },
        loadValues: async ({ search }) => {
            if (!values.currentProjectId) {
                // Report a failure rather than stay in 'loading'. The project load or a reopened dropdown retries it.
                actions.setValuesFailed(search)
                return
            }
            cache.pendingSearches ??= new Set<string>()
            if (cache.pendingSearches.has(search)) {
                return
            }
            cache.pendingSearches.add(search)
            try {
                const response = await eventsValuesRetrieve(String(values.currentProjectId), {
                    key: props.propertyName,
                    event_name: QUICK_FILTER_VALUE_EVENT_NAMES[props.context],
                    ...(search ? { value: search } : {}),
                })
                if (!cache.disposables.isDisposed) {
                    actions.setValues(search, toValueNames(response.results))
                }
            } catch {
                if (!cache.disposables.isDisposed) {
                    actions.setValuesFailed(search)
                }
            } finally {
                cache.pendingSearches.delete(search)
            }
        },
        loadCurrentProjectSuccess: () => {
            if (!Object.hasOwn(values.valuesBySearch, values.search)) {
                actions.loadValues(values.search)
            }
        },
    })),

    // Load before the dropdown opens, so the values are ready when the user clicks
    afterMount(({ actions }) => {
        actions.loadValues('')
    }),
])
