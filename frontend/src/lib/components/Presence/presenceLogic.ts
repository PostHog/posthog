import { MakeLogicType, actions, connect, events, kea, key, listeners, path, props, reducers, selectors } from 'kea'

import { teamLogic } from 'scenes/teamLogic'
import { userLogic } from 'scenes/userLogic'

import { presenceHeartbeatCreate, presenceLeaveCreate } from '~/generated/core/api'
import type { ActivityEnumApi, PresenceViewerApi } from '~/generated/core/api.schemas'
import type { ActivityScope, UserType } from '~/types'

import {
    PRESENCE_COMPOSING_TIMEOUT_MS,
    PRESENCE_HEARTBEAT_INTERVAL_MS,
    PRESENCE_PRUNE_INTERVAL_MS,
    dedupeViewersByUser,
    describePresence,
    getPresenceClientId,
    pruneStaleViewers,
} from './presenceUtils'

export interface PresenceLogicProps {
    /** The same scope string discussions and activity logs use, e.g. `conversations_ticket`. */
    scope: ActivityScope | string
    itemId: string
    /** Names the thing being looked at in the label, e.g. "this ticket". */
    noun?: string
    disabled?: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface presenceLogicValues {
    currentTeamId: number | null // teamLogic
    user: UserType | null // userLogic
    activity: ActivityEnumApi
    otherViewers: PresenceViewerApi[]
    presenceLabel: string | null
    viewers: PresenceViewerApi[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface presenceLogicActions {
    heartbeat: () => {
        value: true
    }
    pruneViewers: (now: number) => {
        now: number
    }
    reportTyping: () => {
        value: true
    }
    setActivity: (activity: ActivityEnumApi) => {
        activity: ActivityEnumApi
    }
    setViewers: (viewers: PresenceViewerApi[]) => {
        viewers: PresenceViewerApi[]
    }
    startPolling: () => {
        value: true
    }
    stopPolling: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface presenceLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        otherViewers: (viewers: PresenceViewerApi[], user: UserType | null) => PresenceViewerApi[]
        presenceLabel: (otherViewers: PresenceViewerApi[], arg: string | undefined) => string | null
    }
}

export type presenceLogicType = MakeLogicType<
    presenceLogicValues,
    presenceLogicActions,
    PresenceLogicProps,
    presenceLogicMeta
>

export const presenceLogic = kea<presenceLogicType>([
    props({} as PresenceLogicProps),
    key((props) => `${props.scope}::${props.itemId}`),
    path((key) => ['lib', 'components', 'Presence', 'presenceLogic', key]),
    connect(() => ({
        values: [teamLogic, ['currentTeamId'], userLogic, ['user']],
    })),
    actions({
        heartbeat: true,
        reportTyping: true,
        setActivity: (activity: ActivityEnumApi) => ({ activity }),
        setViewers: (viewers: PresenceViewerApi[]) => ({ viewers }),
        pruneViewers: (now: number) => ({ now }),
        startPolling: true,
        stopPolling: true,
    }),
    reducers({
        activity: [
            'viewing' as ActivityEnumApi,
            {
                setActivity: (_, { activity }) => activity,
            },
        ],
        viewers: [
            [] as PresenceViewerApi[],
            {
                setViewers: (_, { viewers }) => viewers,
                pruneViewers: (state, { now }) => pruneStaleViewers(state, now),
            },
        ],
    }),
    selectors({
        otherViewers: [
            (s) => [s.viewers, s.user],
            (viewers: PresenceViewerApi[], user: UserType | null): PresenceViewerApi[] =>
                dedupeViewersByUser(viewers).filter((viewer) => viewer.user.id !== user?.id),
        ],
        presenceLabel: [
            (s) => [s.otherViewers, (_, props: PresenceLogicProps) => props.noun],
            (otherViewers: PresenceViewerApi[], noun: string | undefined): string | null =>
                describePresence(otherViewers, noun || 'this page'),
        ],
    }),
    listeners(({ actions, values, props, cache }) => ({
        heartbeat: async () => {
            if (props.disabled || !values.currentTeamId) {
                return
            }
            try {
                const response = await presenceHeartbeatCreate(String(values.currentTeamId), {
                    scope: props.scope,
                    item_id: props.itemId,
                    client_id: getPresenceClientId(),
                    activity: values.activity,
                })
                actions.setViewers(response.results)
            } catch (error) {
                // Presence is decoration. A failure means we show nobody, never a toast.
                console.error('Failed to report presence:', error)
            }
        },
        reportTyping: () => {
            if (values.activity !== 'composing') {
                // Edge-triggered, so "replying..." shows up within a second instead of waiting for
                // the next tick. setActivity sends its own heartbeat.
                actions.setActivity('composing')
            }
            cache.disposables.add(() => {
                const timeoutId = setTimeout(() => actions.setActivity('viewing'), PRESENCE_COMPOSING_TIMEOUT_MS)
                return () => clearTimeout(timeoutId)
            }, 'composingTimeout')
        },
        setActivity: () => {
            actions.heartbeat()
        },
        startPolling: () => {
            actions.heartbeat()
            cache.disposables.add(() => {
                const intervalId = setInterval(() => actions.heartbeat(), PRESENCE_HEARTBEAT_INTERVAL_MS)
                return () => clearInterval(intervalId)
            }, 'presenceHeartbeat')
            // Prune locally too, so avatars fade even when heartbeats are failing.
            cache.disposables.add(() => {
                const intervalId = setInterval(() => actions.pruneViewers(Date.now()), PRESENCE_PRUNE_INTERVAL_MS)
                return () => clearInterval(intervalId)
            }, 'presencePrune')
        },
        stopPolling: () => {
            cache.disposables.dispose('presenceHeartbeat')
            cache.disposables.dispose('presencePrune')
        },
    })),
    events(({ actions, values, props }) => ({
        afterMount: () => {
            if (!props.disabled) {
                actions.startPolling()
            }
        },
        beforeUnmount: () => {
            if (props.disabled || !values.currentTeamId) {
                return
            }
            // Best effort, so the avatar goes as soon as the tab does. The server TTL is the backstop.
            void presenceLeaveCreate(String(values.currentTeamId), {
                scope: props.scope,
                item_id: props.itemId,
                client_id: getPresenceClientId(),
            }).catch(() => {})
        },
    })),
])
