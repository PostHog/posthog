    selectedTab: SidePanelTab | null // sidePanelStateLogic
    sidePanelOpen: boolean // sidePanelStateLogic
    currentProjectId: number | string // teamLogic
    instanceId: string | null
    recentUserMembers: OrganizationMemberType[]
    recentUsers: string[]
