import { MakeLogicType, afterMount, connect, kea, key, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { projectLogic } from 'scenes/projectLogic'

import { dependenciesList } from '~/generated/core/api'
import type { EntityDependencyGroupApi } from '~/generated/core/api.schemas'

export interface EntityDependenciesLogicProps {
    /** Registry entity type, e.g. 'cohort' or 'hog_flow'. */
    type: string
    /** Entity id as a string. */
    id: string
    /** 'used_by' lists what references the entity; 'depends_on' lists what it references. */
    direction: 'used_by' | 'depends_on'
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface entityDependenciesLogicValues {
    currentProjectId: number | null // projectLogic
    groups: EntityDependencyGroupApi[] | null
    groupsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface entityDependenciesLogicActions {
    loadGroups: () => any
    loadGroupsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadGroupsSuccess: (
        groups: EntityDependencyGroupApi[],
        payload?: any
    ) => {
        groups: EntityDependencyGroupApi[]
        payload?: any
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface entityDependenciesLogicMeta {
    key: string
}

export type entityDependenciesLogicType = MakeLogicType<
    entityDependenciesLogicValues,
    entityDependenciesLogicActions,
    EntityDependenciesLogicProps,
    entityDependenciesLogicMeta
>

export const entityDependenciesLogic = kea<entityDependenciesLogicType>([
    path((key) => ['lib', 'components', 'EntityDependencies', 'entityDependenciesLogic', key ?? 'unknown']),
    props({} as EntityDependenciesLogicProps),
    key((props) => `${props.direction}:${props.type}:${props.id}`),
    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),
    loaders(({ props, values }) => ({
        groups: [
            null as EntityDependencyGroupApi[] | null,
            {
                loadGroups: async () => {
                    const params =
                        props.direction === 'used_by'
                            ? { target_type: props.type, target_id: props.id }
                            : { source_type: props.type, source_id: props.id }
                    return await dependenciesList(String(values.currentProjectId), params)
                },
            },
        ],
    })),
    afterMount(({ actions }) => {
        actions.loadGroups()
    }),
])
