import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { subscriptions } from 'kea-subscriptions'
import { match } from 'ts-pattern'

import { GitMetadataParser, supportedProviders } from 'lib/components/Git/gitMetadataParser'

import { teamLogic } from 'scenes/teamLogic'

import {
    errorTrackingGitProviderFileLinksResolveGithubRetrieve,
    errorTrackingGitProviderFileLinksResolveGitlabRetrieve,
} from 'products/error_tracking/frontend/generated/api'

import { stackFrameLogic } from './stackFrameLogic'
import type { KeyedStackFrameRecords } from './stackFrameLogic'

export interface SourceData {
    url: string
    provider: string
}

