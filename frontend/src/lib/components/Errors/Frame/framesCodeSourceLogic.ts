import { MakeLogicType, actions, kea, listeners, path, reducers, selectors } from 'kea'

import { getCurrentTeamId } from 'lib/utils/getAppContext'

import { errorTrackingGitProviderFileLinksResolveCreate } from 'products/error_tracking/frontend/generated/api'

export interface SourceData {
    url: string
    provider: string
}

export interface ResolveSourceUrlsPayload {
    rawIds: string[]
    releaseId: string
}

// A frame's link depends on the release it was captured with: the same frame in two releases
// points at two commits.
function sourceKey(releaseId: string, rawId: string): string {
    return `${releaseId}:${rawId}`
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface framesCodeSourceLogicValues {
    frameSourceUrls: Record<string, SourceData | null>
    getSourceDataForFrame: (rawId: string, releaseId?: string | undefined) => SourceData | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface framesCodeSourceLogicActions {
    resolveSourceUrls: ({ rawIds, releaseId }: ResolveSourceUrlsPayload) => {
        rawIds: string[]
        releaseId: string
    }
    setSourceData: (data: Record<string, SourceData | null>) => {
        data: Record<string, SourceData | null>
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface framesCodeSourceLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        getSourceDataForFrame: (
            frameSourceUrls: Record<string, SourceData | null>
        ) => (rawId: string, releaseId?: string | undefined) => SourceData | null
    }
}

export type framesCodeSourceLogicType = MakeLogicType<
    framesCodeSourceLogicValues,
    framesCodeSourceLogicActions,
    Record<string, any>,
    framesCodeSourceLogicMeta
>

export const framesCodeSourceLogic = kea<framesCodeSourceLogicType>([
    path(['components', 'Errors', 'framesCodeSourceLogic']),

    actions({
        setSourceData: (data: Record<string, SourceData | null>) => ({ data }),
        resolveSourceUrls: ({ rawIds, releaseId }: ResolveSourceUrlsPayload) => ({ rawIds, releaseId }),
    }),

    reducers({
        frameSourceUrls: [
            {} as Record<string, SourceData | null>,
            {
                setSourceData: (state, { data }) => ({
                    ...state,
                    ...data,
                }),
            },
        ],
    }),

    listeners(({ actions, values, cache }) => ({
        resolveSourceUrls: async ({ rawIds, releaseId }) => {
            const pending: Set<string> = (cache.pendingKeys ??= new Set<string>())
            const unresolved = rawIds.filter((rawId) => {
                const key = sourceKey(releaseId, rawId)
                return values.frameSourceUrls[key] === undefined && !pending.has(key)
            })
            if (unresolved.length === 0) {
                return
            }
            unresolved.forEach((rawId) => pending.add(sourceKey(releaseId, rawId)))

            try {
                const { results } = await errorTrackingGitProviderFileLinksResolveCreate(String(getCurrentTeamId()), {
                    release_id: releaseId,
                    raw_ids: unresolved,
                })
                // Frames the server did not link are stored as null so the next load does not ask again.
                const data: Record<string, SourceData | null> = Object.fromEntries(
                    unresolved.map((rawId) => [sourceKey(releaseId, rawId), null])
                )
                for (const link of results) {
                    data[sourceKey(releaseId, link.raw_id)] = { url: link.url, provider: link.provider }
                }
                actions.setSourceData(data)
            } finally {
                unresolved.forEach((rawId) => pending.delete(sourceKey(releaseId, rawId)))
            }
        },
    })),

    selectors({
        getSourceDataForFrame: [
            (s) => [s.frameSourceUrls],
            (frameSourceUrls: Record<string, SourceData | null>) =>
                (rawId: string, releaseId?: string): SourceData | null =>
                    releaseId ? frameSourceUrls[sourceKey(releaseId, rawId)] || null : null,
        ],
    }),
])
