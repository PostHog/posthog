import {
    LogicWrapper,
    MakeLogicType,
    actions,
    afterMount,
    connect,
    kea,
    key,
    path,
    props,
    reducers,
    selectors,
} from 'kea'
import { loaders } from 'kea-loaders'

import { teamLogic } from 'scenes/teamLogic'

import { errorTrackingGitProviderFileLinksSourceFileRetrieve } from 'products/error_tracking/frontend/generated/api'
import type { FrameSourceFileResponseApi } from 'products/error_tracking/frontend/generated/api.schemas'

import { CapturedCodeCheck, SourceFileWindow, checkCapturedCode, sourceFileWindow } from './sourceFileWindow'

export interface FrameSourceFileTarget {
    eventUuid: string
    eventTimestamp: string
    rawId: string
}

export interface FrameSourceFileLogicProps extends FrameSourceFileTarget {
    capturedLine: string | null
}

const INITIAL_LINES = 15
const MORE_LINES = 100

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface frameSourceFileLogicValues {
    currentProjectId: number | string // teamLogic
    capturedCodeCheck: CapturedCodeCheck | null
    fileWindow: SourceFileWindow | null
    linesAbove: number
    linesBelow: number
    sourceFile: FrameSourceFileResponseApi | null
    sourceFileLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface frameSourceFileLogicActions {
    loadSourceFile: () => any
    loadSourceFileFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadSourceFileSuccess: (
        sourceFile: FrameSourceFileResponseApi | null,
        payload?: any
    ) => {
        sourceFile: FrameSourceFileResponseApi | null
        payload?: any
    }
    showMoreAbove: () => {
        value: true
    }
    showMoreBelow: () => {
        value: true
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface frameSourceFileLogicMeta {
    key: string
    __keaTypeGenInternalSelectorTypes: {
        fileWindow: (
            sourceFile: FrameSourceFileResponseApi | null,
            linesAbove: 15,
            linesBelow: 15
        ) => SourceFileWindow | null
        capturedCodeCheck: (sourceFile: FrameSourceFileResponseApi | null, arg: any) => CapturedCodeCheck | null
    }
}

export type frameSourceFileLogicType = MakeLogicType<
    frameSourceFileLogicValues,
    frameSourceFileLogicActions,
    FrameSourceFileLogicProps,
    frameSourceFileLogicMeta
>

export const frameSourceFileLogic: LogicWrapper<frameSourceFileLogicType> = kea<frameSourceFileLogicType>([
    props({} as FrameSourceFileLogicProps),
    key(({ eventUuid, rawId }) => `${eventUuid}:${rawId}`),
    path((key) => ['components', 'Errors', 'Frame', 'frameSourceFileLogic', key]),

    connect(() => ({
        values: [teamLogic, ['currentProjectId']],
    })),

    actions({
        showMoreAbove: true,
        showMoreBelow: true,
    }),

    loaders(({ props, values }) => ({
        sourceFile: [
            null as FrameSourceFileResponseApi | null,
            {
                loadSourceFile: async () => {
                    try {
                        return await errorTrackingGitProviderFileLinksSourceFileRetrieve(
                            String(values.currentProjectId),
                            {
                                event_uuid: props.eventUuid,
                                event_timestamp: props.eventTimestamp,
                                frame_raw_id: props.rawId,
                            }
                        )
                    } catch {
                        // The API answers 404 when the frame has no readable file. The captured
                        // context stays, so this is not an error for the person looking at it.
                        return null
                    }
                },
            },
        ],
    })),

    reducers({
        linesAbove: [INITIAL_LINES as number, { showMoreAbove: (lines) => lines + MORE_LINES }],
        linesBelow: [INITIAL_LINES as number, { showMoreBelow: (lines) => lines + MORE_LINES }],
    }),

    selectors({
        fileWindow: [
            (s) => [s.sourceFile, s.linesAbove, s.linesBelow],
            (
                sourceFile: FrameSourceFileResponseApi | null,
                linesAbove: number,
                linesBelow: number
            ): SourceFileWindow | null =>
                sourceFile ? sourceFileWindow(sourceFile.lines, sourceFile.line, linesAbove, linesBelow) : null,
        ],
        capturedCodeCheck: [
            (s) => [s.sourceFile, (_, props) => props.capturedLine],
            (sourceFile: FrameSourceFileResponseApi | null, capturedLine: string | null): CapturedCodeCheck | null =>
                sourceFile ? checkCapturedCode(sourceFile.lines, sourceFile.line, capturedLine) : null,
        ],
    }),

    afterMount(({ actions }) => {
        actions.loadSourceFile()
    }),
])
