/**
 * Measures how much client-side capture an ad blocker is taking away.
 *
 * posthog-js stamps `$sdk_debug_recording_script_not_loaded` on every event it sends from a page
 * where the recorder script never loaded, which is almost always an ad blocker. Those sessions
 * produce no recording at all, so the flag is the only trace of them.
 *
 * Nothing loads on mount: the query scans a week of events, so each consumer asks for it only when
 * it can act on the answer.
 */
export const adBlockedCaptureLogic = kea<adBlockedCaptureLogicType>([
    path(['lib', 'components', 'AdBlockedCapture', 'adBlockedCaptureLogic']),
    loaders(({ values, cache }) => ({
        adBlockedCaptureStats: [
            // null until the query resolves — consumers must distinguish "not yet measured" from a
            // measured zero so they don't act before the result is in.
            null as AdBlockedCaptureStats | null,
            {
                loadAdBlockedCaptureStats: async () => {
                    if (cache.lastCheckedTimestamp > Date.now() - CHECK_INTERVAL_MS) {
                        return values.adBlockedCaptureStats
                    }

                    cache.lastCheckedTimestamp = Date.now()

                    const query = hogql`
                        SELECT
                            uniqIf($session_id, properties.$sdk_debug_recording_script_not_loaded = true) AS blocked_sessions,
                            uniq($session_id) AS total_sessions
                        FROM events
                        WHERE event IN ('$pageview', '$screen')
                        AND timestamp >= now() - INTERVAL 7 DAY
                        AND timestamp <= now()
                        AND $session_id IS NOT NULL`

                    const currentScene = sceneLogic.findMounted()?.values.activeSceneId ?? 'Replay'
                    try {
                        const response = await api.queryHogQL(query, {
                            scene: currentScene,
                            productKey: 'session_replay',
                        })
                        const row = response.results?.[0]
                        if (!row) {
                            return values.adBlockedCaptureStats
                        }
                        return {
                            blockedSessions: Number(row[0]) || 0,
                            totalSessions: Number(row[1]) || 0,
                        }
                    } catch (error) {
                        // The measurement only decorates a nudge and a settings row. Swallow errors so
                        // kea-loaders does not raise a toast on a page the user came to for something else.
                        posthog.captureException(error, {
                            posthog_source: 'adBlockedCaptureLogic.loadAdBlockedCaptureStats',
                        })
                        return values.adBlockedCaptureStats
                    }
                },
            },
        ],
    })),
    selectors({
        adBlockedCaptureShare: [
            (s) => [s.adBlockedCaptureStats],
            (stats: AdBlockedCaptureStats | null): number | null =>
                stats && stats.totalSessions > 0 ? stats.blockedSessions / stats.totalSessions : null,
        ],
        hasSignificantAdBlockedCapture: [
            (s) => [s.adBlockedCaptureStats, s.adBlockedCaptureShare],
            (stats: AdBlockedCaptureStats | null, share: number | null): boolean | null =>
                stats === null
                    ? null
                    : stats.totalSessions >= AD_BLOCKED_CAPTURE_MINIMUM_SESSIONS &&
                      share !== null &&
                      share >= AD_BLOCKED_CAPTURE_SHARE_THRESHOLD,
        ],
    }),
])
