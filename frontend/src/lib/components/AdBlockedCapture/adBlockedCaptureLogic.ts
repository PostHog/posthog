import { MakeLogicType, actions, kea, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'
import posthog from 'posthog-js'

import api from 'lib/api'
import { getCurrentTeamIdOrNone } from 'lib/utils/getAppContext'
import { sceneLogic } from 'scenes/sceneLogic'

import { hogql } from '~/queries/utils'

export interface AdBlockedCaptureStats {
    blockedSessions: number
    totalSessions: number
}

/** Days of traffic the share is measured over. */
export const AD_BLOCKED_CAPTURE_WINDOW_DAYS = 7
/** Share of blocked sessions that makes the loss worth telling someone about. */
export const AD_BLOCKED_CAPTURE_SHARE_THRESHOLD = 0.05
/** Below this many sessions, one blocked session moves the share too much to act on. */
export const AD_BLOCKED_CAPTURE_MINIMUM_SESSIONS = 50

const CHECK_INTERVAL_MS = 1000 * 60 * 10 // 10 minutes

// Held outside the logic so it survives an unmount. The nav banner mounts and unmounts as the user
// moves between scenes, and the settings row asks for the same number, so a per-mount cache would
// rerun a week-wide scan on every navigation. The team is part of the key because each environment
// has its own loss rate.
let lastMeasurement: { teamId: number | null; at: number; stats: AdBlockedCaptureStats | null } | null = null

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface adBlockedCaptureLogicValues {
    adBlockedCaptureFailed: boolean
    adBlockedCaptureShare: number | null
    adBlockedCaptureStats: AdBlockedCaptureStats | null
    adBlockedCaptureStatsLoading: boolean
    hasSignificantAdBlockedCapture: boolean | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface adBlockedCaptureLogicActions {
    loadAdBlockedCaptureStats: () => any
    loadAdBlockedCaptureStatsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAdBlockedCaptureStatsSuccess: (
        adBlockedCaptureStats: AdBlockedCaptureStats | null,
        payload?: any
    ) => {
        adBlockedCaptureStats: AdBlockedCaptureStats | null
        payload?: any
    }
    setMeasurementFailed: (failed: boolean) => {
        failed: boolean
    }
}

