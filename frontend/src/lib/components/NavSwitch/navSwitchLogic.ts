/**
 * Switches between the old and the new navigation. `Navigation` keeps it mounted under both, so the
 * early access lookup runs once and the new navigation's dialog survives the in-place swap.
 */
export const navSwitchLogic = kea<navSwitchLogicType>([
    path(['lib', 'components', 'NavSwitch', 'navSwitchLogic']),
    connect(() => ({
        values: [featureFlagLogic, ['featureFlags'], featurePreviewsLogic, ['earlyAccessFeatures']],
        actions: [
            featurePreviewsLogic,
            ['loadEarlyAccessFeatures', 'updateEarlyAccessFeatureEnrollment'],
            helpMenuLogic,
            ['setHelpMenuOpen', 'toggleHelpMenu'],
            navPanelAdvertisementLogic(NAV_SWITCH_CARD_LOGIC_PROPS),
            ['showAdvertisement'],
        ],
    })),
    actions({
        switchNav: (surface: NavSwitchSurface) => ({ surface }),
        setNewNavDialogOpen: (open: boolean) => ({ open }),
        /** Someone closed the "PostHog is changing" dialog without picking an action. */
        dismissNewNavDialog: true,
        /** The dialog finished its closing animation. */
        newNavDialogClosed: true,
        showSwitchHint: true,
        hideSwitchHint: true,
    }),
    reducers({
        newNavDialogOpen: [
            false,
            {
                setNewNavDialogOpen: (_, { open }) => open,
                dismissNewNavDialog: () => false,
            },
        ],
        // A dismissal points at where the switch stays, once the dialog has finished closing. The dialog's buttons
        // close it with `setNewNavDialogOpen`, which is not a dismissal.
        switchHintPending: [
            false,
            {
                dismissNewNavDialog: () => true,
                setNewNavDialogOpen: () => false,
                showSwitchHint: () => false,
            },
        ],
        // Points at the switch in the "More" menu, on either navigation, until that menu closes.
        switchHintVisible: [
            false,
            {
                showSwitchHint: () => true,
                hideSwitchHint: () => false,
                setHelpMenuOpen: (state, { isOpen }) => isOpen && state,
                toggleHelpMenu: () => false,
            },
        ],
    }),
    selectors({
        newNavOn: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV],
        ],
        switchFlagOn: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.TODAY_RAIL_NAV_SWITCH],
        ],
        todayNavFeature: [
            (s) => [s.earlyAccessFeatures],
            (earlyAccessFeatures: EnrichedEarlyAccessFeature[]): EnrichedEarlyAccessFeature | null =>
                earlyAccessFeatures.find((feature) => feature.flagKey === FEATURE_FLAGS.TODAY_RAIL_NAV) ?? null,
        ],
        // The old navigation switches through the early access feature, so it needs the feature to exist.
        // The new navigation can always switch back.
        switchAvailable: [
            (s) => [s.switchFlagOn, s.newNavOn, s.todayNavFeature],
            (switchFlagOn: boolean, newNavOn: boolean, todayNavFeature: EnrichedEarlyAccessFeature | null): boolean =>
                switchFlagOn && (newNavOn || !!todayNavFeature),
        ],
        switchLabel: [
            (s) => [s.newNavOn],
            (newNavOn: boolean): string => (newNavOn ? 'Use old navigation' : 'Try new design'),
        ],
        needsEarlyAccessFeatures: [
            (s) => [s.switchFlagOn, s.newNavOn],
            (switchFlagOn: boolean, newNavOn: boolean): boolean => switchFlagOn && !newNavOn,
        ],
    }),
    listeners(({ actions, values }) => ({
        switchNav: ({ surface }) => {
            const turningOn = !values.newNavOn
            // pinned: analytics event names and properties. The exit survey triggers on the off event.
            posthog.capture(turningOn ? 'today nav switched on' : 'today nav switched off', { surface })
            // Set before the enrollment update, which swaps the navigation, so the new navigation opens
            // with its dialog already set. The dialog replaces a toast when switching on.
            actions.setNewNavDialogOpen(turningOn)
            actions.updateEarlyAccessFeatureEnrollment(
                FEATURE_FLAGS.TODAY_RAIL_NAV,
                turningOn,
                values.todayNavFeature?.stage
            )
            if (!turningOn) {
                // Someone who comes back gets the sunset card again, even if they dismissed it before they left.
                actions.showAdvertisement()
                lemonToast.success('You are back on the old navigation. Switch to the new navigation any time.')
            }
        },
        newNavDialogClosed: () => {
            if (values.switchHintPending) {
                actions.showSwitchHint()
            }
        },
        showSwitchHint: () => {
            actions.setHelpMenuOpen(true)
        },
    })),
    subscriptions(({ actions }) => ({
        needsEarlyAccessFeatures: (needsEarlyAccessFeatures: boolean) => {
            if (needsEarlyAccessFeatures) {
                actions.loadEarlyAccessFeatures()
            }
        },
    })),
])
