/**
 * The user's custom facets for one product's facet rail, persisted server-side (per user, per team)
 * so they follow the user across devices. Keyed by product, not by viewer id: the underlying setting
 * is one row per user/team/product, not one per rail instance.
 */
export const customFacetsLogic = kea<customFacetsLogicType>([
    props({} as CustomFacetsLogicProps),
    key((props) => props.product),
    path((key) => ['lib', 'components', 'FacetRail', 'customFacetsLogic', key]),

    connect(() => ({ values: [featureFlagLogic, ['featureFlags']] })),

    actions({
        loadEntries: true,
        addCustomFacet: (key: string, sourceType: CustomFacetSourceType) => ({ key, sourceType }),
        removeCustomFacet: (key: string, sourceType: CustomFacetSourceType) => ({ key, sourceType }),
    }),

    loaders(({ props, values }) => {
        const params = { product: props.product }
        // The PATCH replaces the whole server-side list, so a mutation must build on the persisted
        // entries: local state can be empty when the load failed or never ran, and using it as the
        // base would wipe the user's saved facets.
        const baseEntries = async (): Promise<UserFacetSettingsEntryApi[]> =>
            values.entriesLoaded ? values.entries : (await userFacetSettingsRetrieve('@me', params)).custom_facets
        return {
            entries: [
                [] as UserFacetSettingsEntryApi[],
                {
                    loadEntries: async () => {
                        const response = await userFacetSettingsRetrieve('@me', params)
                        return response.custom_facets
                    },
                    addCustomFacet: async ({ key, sourceType }) => {
                        const base = await baseEntries()
                        if (base.some((entry) => entry.key === key && entry.source_type === sourceType)) {
                            return base
                        }
                        const nextEntries = [...base, { key, source_type: sourceType }]
                        await userFacetSettingsPartialUpdate('@me', params, { custom_facets: nextEntries })
                        return nextEntries
                    },
                    removeCustomFacet: async ({ key, sourceType }) => {
                        const base = await baseEntries()
                        const nextEntries = base.filter(
                            (entry) => !(entry.key === key && entry.source_type === sourceType)
                        )
                        await userFacetSettingsPartialUpdate('@me', params, { custom_facets: nextEntries })
                        return nextEntries
                    },
                },
            ],
        }
    }),

    reducers({
        entriesLoaded: [
            false,
            {
                loadEntriesSuccess: () => true,
            },
        ],
    }),

    selectors({
        // A primitive, so downstream facet identities only change when the gate actually flips —
        // the featureFlags object gets a fresh identity on every flag refresh.
        customFacetsEnabled: [
            (s) => [s.featureFlags],
            (featureFlags: FeatureFlagsSet): boolean => !!featureFlags[FEATURE_FLAGS.CUSTOM_FACET_PINNING],
        ],
        // Each product turns these into its own facet configs, since the filter a facet writes is product-specific.
        customFacetEntries: [
            (s) => [s.entries, s.customFacetsEnabled],
            (entries: UserFacetSettingsEntryApi[], customFacetsEnabled: boolean): UserFacetSettingsEntryApi[] =>
                customFacetsEnabled ? entries : [],
        ],
    }),

    listeners(({ actions, values }) => ({
        // Flags resolve asynchronously and often land after this logic mounts — without this, a
        // flagged user's pinned facets would stay unloaded for the whole session.
        [featureFlagLogic.actionTypes.setFeatureFlags]: () => {
            if (values.customFacetsEnabled && !values.entriesLoaded && !values.entriesLoading) {
                actions.loadEntries()
            }
        },
    })),

    events(({ actions, values }) => ({
        afterMount: () => {
            if (values.customFacetsEnabled) {
                actions.loadEntries()
            }
        },
    })),
])
