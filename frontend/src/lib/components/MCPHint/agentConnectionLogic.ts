import { MakeLogicType, actions, afterMount, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import type { ConnectedApp } from 'scenes/settings/user/connectedAppsLogic'

const POLL_INTERVAL_MS = 3000

/**
 * Whether the user has an agent connected to PostHog. The MCP server signs agents in through OAuth,
 * and the API does not tell an MCP client apart from other OAuth apps, so any connection counts
 * except the setup wizard's, which signs in to install the SDK.
 */
export function hasAgentConnection(connectedApps: ConnectedApp[]): boolean {
    return connectedApps.some((app) => !app.is_setup_wizard)
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface agentConnectionLogicValues {
    connectedApps: ConnectedApp[] | null
    connectedAppsLoading: boolean
    hasConnectedAgent: boolean | null
    polling: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface agentConnectionLogicActions {
    loadConnectedApps: (_?: any) => any
    loadConnectedAppsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadConnectedAppsSuccess: (
        connectedApps: ConnectedApp[] | null,
        payload?: any
    ) => {
        connectedApps: ConnectedApp[] | null
        payload?: any
    }
    setPolling: (polling: boolean) => {
        polling: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface agentConnectionLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        hasConnectedAgent: (connectedApps: any) => boolean | null
    }
}

export type agentConnectionLogicType = MakeLogicType<
    agentConnectionLogicValues,
    agentConnectionLogicActions,
    Record<string, any>,
    agentConnectionLogicMeta
>

/**
 * Promotional surfaces read this instead of `connectedAppsLogic`: a failed lookup stays silent and
 * leaves the answer unknown, rather than raising the settings page's error toast.
 */
export const agentConnectionLogic = kea<agentConnectionLogicType>([
    path(['lib', 'components', 'MCPHint', 'agentConnectionLogic']),
    actions({
        setPolling: (polling: boolean) => ({ polling }),
    }),
    reducers({
        polling: [
            false,
            {
                setPolling: (_, { polling }) => polling,
            },
        ],
    }),
    loaders(({ values }) => ({
        connectedApps: [
            null as ConnectedApp[] | null,
            {
                loadConnectedApps: async (_, breakpoint) => {
                    let connectedApps: ConnectedApp[]
                    try {
                        // nosemgrep: prefer-codegen-api -- the connected apps endpoint is not in the generated client; connectedAppsLogic makes the same call.
                        connectedApps = await api.get<ConnectedApp[]>('api/oauth/connected-apps/')
                    } catch {
                        return values.connectedApps
                    }
                    // Drops a slower, older response so it cannot overwrite a newer one.
                    breakpoint()
                    return connectedApps
                },
            },
        ],
    })),
    selectors({
        // `null` until a lookup succeeds, so callers can tell "not connected" from "unknown".
        hasConnectedAgent: [
            (s) => [s.connectedApps],
            (connectedApps: ConnectedApp[] | null): boolean | null =>
                connectedApps === null ? null : hasAgentConnection(connectedApps),
        ],
    }),
    listeners(({ actions, values, cache }) => ({
        setPolling: ({ polling }) => {
            if (polling) {
                actions.loadConnectedApps()
            } else {
                cache.disposables.dispose('poll')
            }
        },
        // The next poll starts only after the previous one returns, so requests never overlap.
        loadConnectedAppsSuccess: () => {
            if (!values.polling || values.hasConnectedAgent) {
                return
            }
            cache.disposables.add(() => {
                const id = window.setTimeout(() => actions.loadConnectedApps(), POLL_INTERVAL_MS)
                return () => window.clearTimeout(id)
            }, 'poll')
        },
    })),
    afterMount(({ actions, values, cache }) => {
        actions.loadConnectedApps()
        // An agent is usually authorized in another tab, so check again when the user comes back.
        cache.disposables.add(() => {
            const onFocus = (): void => {
                if (!values.hasConnectedAgent) {
                    actions.loadConnectedApps()
                }
            }
            window.addEventListener('focus', onFocus)
            return () => window.removeEventListener('focus', onFocus)
        }, 'focusRefresh')
    }),
])
