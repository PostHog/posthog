export const tagSelectLogic = kea<tagSelectLogicType>([
    props({} as TagSelectLogicProps),
    key((props) => props.logicKey),
    path((logicKey) => ['lib', 'components', 'tagSelectLogic', logicKey]),
    actions(() => ({
        setSearch: (search: string) => ({ search }),
        setShowPopover: (visible: boolean) => ({ visible }),
        loadMoreTags: (loadTags: LoadTags) => ({ loadTags }),
    })),
    loaders(({ values }) => ({
        tagPage: [
            null as TagPage | null,
            {
                loadTagPage: async (
                    {
                        search,
                        offset,
                        loadTags,
                        requestEpoch,
                    }: { search: string; offset: number; loadTags: LoadTags; requestEpoch: number },
                    breakpoint
                ): Promise<TagPage> => {
                    if (offset === 0 && search) {
                        await breakpoint(200)
                    }
                    const isStale = (): boolean => {
                        try {
                            breakpoint()
                        } catch {
                            return true
                        }
                        return requestEpoch !== values.requestEpoch
                    }
                    try {
                        const page = await loadTags(search, offset, isStale)
                        breakpoint()
                        return requestEpoch === values.requestEpoch ? page : { results: [], hasMore: false }
                    } catch (error) {
                        breakpoint()
                        if (requestEpoch !== values.requestEpoch) {
                            return { results: [], hasMore: false }
                        }
                        throw error
                    }
                },
            },
        ],
    })),
    reducers(() => ({
        awaitingFirstPage: [
            false,
            {
                setSearch: () => true,
                setShowPopover: (_, { visible }) => visible,
                loadTagPageSuccess: (state, { payload }) => (payload?.offset === 0 ? false : state),
                loadTagPageFailure: () => false,
            },
        ],
        search: [
            '',
            {
                setSearch: (_, { search }) => search,
                setShowPopover: (state, { visible }) => (visible ? state : ''),
            },
        ],
        requestEpoch: [
            0,
            {
                setSearch: (state) => state + 1,
                setShowPopover: (state, { visible }) => (visible ? state : state + 1),
            },
        ],
        showPopover: [false, { setShowPopover: (_, { visible }) => visible }],
        tagResults: [
            [] as TagOption[],
            {
                setSearch: () => [],
                setShowPopover: (state, { visible }) => (visible ? state : []),
                loadTagPageSuccess: (state, { tagPage, payload }) =>
                    payload?.offset === 0 ? tagPage.results : [...state, ...tagPage.results],
            },
        ],
        nextOffset: [
            0,
            {
                setSearch: () => 0,
                setShowPopover: () => 0,
                loadTagPageSuccess: (_, { tagPage, payload }) =>
                    tagPage.nextOffset ?? (payload?.offset ?? 0) + tagPage.results.length,
            },
        ],
        hasMoreTags: [
            false,
            {
                setSearch: () => false,
                setShowPopover: (_, { visible }) => visible,
                loadTagPageSuccess: (_, { tagPage }) => tagPage.hasMore,
            },
        ],
        tagPageError: [
            null as string | null,
            {
                setSearch: () => null,
                setShowPopover: () => null,
                loadTagPageSuccess: () => null,
                loadTagPageFailure: (_, { error }) => error,
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        // Reads the state when it runs, not from a render, because scroll events can fire several times before the next render.
        loadMoreTags: ({ loadTags }) => {
            if (values.hasMoreTags && !values.awaitingFirstPage && !values.tagPageLoading && !values.tagPageError) {
                actions.loadTagPage({
                    search: values.search,
                    offset: values.nextOffset,
                    loadTags,
                    requestEpoch: values.requestEpoch,
                })
            }
        },
    })),
])
