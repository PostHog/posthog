export function exampleSourceFor(
    activeGroup: TaxonomicFilterGroup | undefined,
    eventNames: string[] = []
): ExampleSource | null {
    if (activeGroup?.type === TaxonomicFilterGroupType.EventProperties && eventNames.length) {
        return { kind: 'event', eventNames }
    }
    if (activeGroup?.type === TaxonomicFilterGroupType.PersonProperties) {
        return { kind: 'person', eventNames }
    }
    if (
        activeGroup?.groupTypeIndex !== undefined &&
        String(activeGroup.type).startsWith(TaxonomicFilterGroupType.GroupsPrefix)
    ) {
        return { kind: 'group', groupTypeIndex: activeGroup.groupTypeIndex }
    }
    return null
}

export function exampleFromEvent(event: EventType): Example {
    return { id: event.uuid ?? event.id, label: event.event, timestamp: event.timestamp, properties: event.properties }
}

export function examplesFromPeople(rows: [RecentPersonRow, string][]): Example[] {
    const seen = new Set<string>()
    return rows
        .filter(([person]) => !!person.uuid && !seen.has(person.uuid) && seen.add(person.uuid))
        .slice(0, EXAMPLE_COUNT)
        .map(([person, timestamp]) => ({
            id: person.uuid as string,
            label: asDisplay(person),
            timestamp,
            properties: person.properties ?? {},
        }))
}

export function exampleFromGroup([key, properties, createdAt]: [string, string, string]): Example {
    const parsed = JSON.parse(properties || '{}')
    return { id: key, label: groupDisplayId(key, parsed), timestamp: createdAt, properties: parsed }
}

export function isSelectableValue(value: unknown): value is string | number | boolean {
    return typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean'
}

export const taxonomicExampleBrowserLogic: LogicWrapper<taxonomicExampleBrowserLogicType> =
    kea<taxonomicExampleBrowserLogicType>([
        props({} as TaxonomicFilterLogicProps),
        key((props) => props.taxonomicFilterLogicKey),
        path((key) => ['lib', 'components', 'TaxonomicFilter', 'taxonomicExampleBrowserLogic', key]),
        connect((props: TaxonomicFilterLogicProps) => ({
            values: [
                featureFlagLogic,
                ['featureFlags'],
                preflightLogic,
                ['isCloudOrDev'],
                taxonomicFilterLogic(props),
                ['searchQuery', 'activeTaxonomicGroup'],
                groupsModel,
                ['aggregationLabel'],
            ],
            actions: [taxonomicFilterLogic(props), ['selectItem', 'setActiveTab']],
        })),
        actions({
            resetExamples: true,
            openExampleBrowser: true,
            closeExampleBrowser: true,
            showNextExample: true,
            showPreviousExample: true,
            setHidePostHogProperties: (hide: boolean) => ({ hide }),
            selectExampleKey: (key: string) => ({ key }),
            selectExampleValue: (key: string, value: string) => ({ key, value }),
        }),
        loaders(({ values }) => ({
            examples: [
                [] as Example[],
                {
                    loadExamples: async () => {
                        const source = values.exampleSource
                        if (!source) {
                            return []
                        }
                        if (source.kind === 'group') {
                            const response = await api.query(recentGroupsQuery(source.groupTypeIndex))
                            return (response.results as [string, string, string][]).map(exampleFromGroup)
                        }
                        const response = await api.query(recentEventsQuery(source))
                        return source.kind === 'person'
                            ? examplesFromPeople(response.results as [RecentPersonRow, string][])
                            : response.results.map(([event]: EventType[]) => exampleFromEvent(event))
                    },
                },
            ],
        })),
        reducers({
            examples: {
                resetExamples: () => [],
            },
            isOpen: [
                false,
                {
                    openExampleBrowser: () => true,
                    closeExampleBrowser: () => false,
                },
            ],
            exampleIndex: [
                0,
                {
                    loadExamplesSuccess: () => 0,
                    resetExamples: () => 0,
                    showNextExample: (index) => index + 1,
                    showPreviousExample: (index) => Math.max(0, index - 1),
                },
            ],
            hidePostHogProperties: [
                true,
                {
                    setHidePostHogProperties: (_, { hide }) => hide,
                },
            ],
        }),
        selectors({
            exampleSource: [
                (s) => [s.activeTaxonomicGroup, (_, props) => props.eventNames],
                (
                    activeGroup: TaxonomicFilterGroup | undefined,
                    eventNames: string[] | undefined
                ): ExampleSource | null => exampleSourceFor(activeGroup, eventNames),
            ],
            exampleNoun: [
                (s) => [s.exampleSource, s.aggregationLabel],
                (exampleSource: ExampleSource | null, aggregationLabel: (index: number) => Noun): Noun => {
                    switch (exampleSource?.kind) {
                        case 'person':
                            return { singular: 'person', plural: 'people' }
                        case 'group':
                            return aggregationLabel(exampleSource.groupTypeIndex)
                        default:
                            return { singular: 'event', plural: 'events' }
                    }
                },
            ],
            isAvailable: [
                (s) => [s.featureFlags, s.exampleSource],
                (
                    featureFlags: Record<string, boolean | string | undefined>,
                    exampleSource: ExampleSource | null
                ): boolean => !!featureFlags[FEATURE_FLAGS.TAXONOMIC_FILTER_EXAMPLE_BROWSER] && exampleSource !== null,
            ],
            // Both props promise the host handles `isQuickFilterItem` in its onChange, which is
            // all a value click needs. A host without either would commit the value as a key.
            supportsValueSelection: [
                () => [(_, props) => props.enableKeywordShortcuts, (_, props) => props.collapseUrlsToContainsRow],
                (enableKeywordShortcuts, collapseUrlsToContainsRow): boolean =>
                    !!enableKeywordShortcuts || !!collapseUrlsToContainsRow,
            ],
            currentExample: [
                (s) => [s.examples, s.exampleIndex],
                (examples: Example[], exampleIndex: number): Example | null => examples[exampleIndex] ?? null,
            ],
            hasPreviousExample: [(s) => [s.exampleIndex], (exampleIndex: number): boolean => exampleIndex > 0],
            hasNextExample: [
                (s) => [s.examples, s.exampleIndex],
                (examples: Example[], exampleIndex: number): boolean => exampleIndex < examples.length - 1,
            ],
            visibleProperties: [
                (s) => [s.currentExample, s.hidePostHogProperties, s.isCloudOrDev, s.searchQuery],
                (
                    currentExample: Example | null,
                    hidePostHogProperties: boolean,
                    isCloudOrDev: boolean | undefined,
                    searchQuery: string
                ): ExampleProperty[] => {
                    const query = searchQuery.trim().toLowerCase()
                    return Object.entries(currentExample?.properties ?? {})
                        .filter(([key]) => !hidePostHogProperties || !isPostHogProperty(key, isCloudOrDev))
                        .filter(([key, value]) => !query || matchesQuery(key, value, query))
                        .sort(([a], [b]) => a.localeCompare(b))
                },
            ],
            exploreUrl: [
                (s) => [s.exampleSource],
                (exampleSource: ExampleSource | null): string | null => {
                    if (!exampleSource) {
                        return null
                    }
                    if (exampleSource.kind === 'person') {
                        return urls.persons()
                    }
                    if (exampleSource.kind === 'group') {
                        return urls.groups(exampleSource.groupTypeIndex)
                    }
                    const defaultQuery = getDefaultEventsSceneQuery()
                    const query = {
                        ...defaultQuery,
                        source: {
                            ...defaultQuery.source,
                            after: EXAMPLE_LOOKBACK,
                            ...eventNamesFilter(exampleSource.eventNames),
                        },
                    }
                    return combineUrl(urls.activity(ActivityTab.ExploreEvents), {}, { q: query }).url
                },
            ],
        }),
        listeners(({ actions, values, props }) => ({
            openExampleBrowser: () => {
                posthog.capture('taxonomic filter example browser opened', {
                    surface: legacyTaxonomicSurface(
                        values.featureFlags[FEATURE_FLAGS.TAXONOMIC_FILTER_CATEGORY_DROPDOWN]
                    ),
                    sourceKind: values.exampleSource?.kind,
                    eventName: props.eventNames?.[0],
                })
                if (values.examples.length === 0 && !values.examplesLoading) {
                    actions.loadExamples()
                }
            },
            selectExampleKey: ({ key }) => {
                const group = values.activeTaxonomicGroup
                if (group && values.exampleSource) {
                    actions.selectItem(group, key, { name: key }, { wasFromExample: true })
                }
            },
            selectExampleValue: ({ key, value }) => {
                const group = values.activeTaxonomicGroup
                const source = values.exampleSource
                if (!group || !source || !values.supportsValueSelection) {
                    return
                }
                const item: QuickFilterItem = {
                    _type: 'quick_filter',
                    name: `${key} = ${value}`,
                    filterValue: value,
                    operator: PropertyOperator.Exact,
                    propertyKey: key,
                    ...quickFilterTarget(source),
                }
                actions.selectItem(group, key, item, { wasFromExample: true })
            },
            // Each tab has its own source, so examples loaded for one tab are wrong for the next.
            setActiveTab: () => {
                actions.resetExamples()
                actions.closeExampleBrowser()
            },
        })),
        propsChanged(({ actions, props }, oldProps) => {
            // A series that swaps its event needs examples of the new event, not the old one.
            if (props.eventNames !== oldProps.eventNames) {
                actions.resetExamples()
                actions.closeExampleBrowser()
            }
        }),
    ])

function recentEventsQuery(source: Extract<ExampleSource, { kind: 'event' | 'person' }>): EventsQuery {
    return {
        kind: NodeKind.EventsQuery,
        select: source.kind === 'person' ? ['person', 'timestamp'] : ['*'],
        orderBy: ['timestamp DESC'],
        after: EXAMPLE_LOOKBACK,
        limit: source.kind === 'person' ? PERSON_EVENT_SAMPLE : EXAMPLE_COUNT,
        ...eventNamesFilter(source.eventNames),
    }
}

function recentGroupsQuery(groupTypeIndex: number): HogQLQuery {
    return {
        kind: NodeKind.HogQLQuery,
        query: hogql`SELECT key, properties, created_at FROM groups WHERE index = ${groupTypeIndex} ORDER BY created_at DESC LIMIT ${EXAMPLE_COUNT}`,
    }
}

function quickFilterTarget(
    source: ExampleSource
): Pick<QuickFilterItem, 'propertyFilterType' | 'eventName' | 'groupTypeIndex'> {
    switch (source.kind) {
        case 'event':
            return { propertyFilterType: PropertyFilterType.Event, eventName: source.eventNames[0] }
        case 'person':
            return { propertyFilterType: PropertyFilterType.Person }
        case 'group':
            return { propertyFilterType: PropertyFilterType.Group, groupTypeIndex: source.groupTypeIndex }
    }
}

function eventNamesFilter(eventNames: string[]): Pick<EventsQuery, 'event' | 'properties'> {
    if (eventNames.length === 0) {
        return {}
    }
    return eventNames.length === 1
        ? { event: eventNames[0] }
        : { properties: [{ type: PropertyFilterType.HogQL, key: hogql`event IN ${eventNames}` }] }
}

function matchesQuery(key: string, value: unknown, query: string): boolean {
    return key.toLowerCase().includes(query) || JSON.stringify(value)?.toLowerCase().includes(query)
}
