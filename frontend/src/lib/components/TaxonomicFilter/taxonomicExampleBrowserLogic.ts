export const EXAMPLE_COUNT = 10
export const EXAMPLE_LOOKBACK = '-30d'
// Recent events repeat the same few people, so sample more rows than examples wanted.
const PERSON_EVENT_SAMPLE = 100

export type ExampleSource =
    | { kind: 'event'; eventNames: string[] }
    | { kind: 'person'; eventNames: string[] }
    | { kind: 'group'; groupTypeIndex: number }

/** One record whose properties the user can browse, in a shape shared by every source kind. */
export interface Example {
    id: string
    label: string
    timestamp: string
    properties: Record<string, unknown>
}

export type ExampleProperty = [key: string, value: unknown]

interface RecentPersonRow {
    uuid?: string
    distinct_id: string
    properties?: Record<string, unknown>
}

