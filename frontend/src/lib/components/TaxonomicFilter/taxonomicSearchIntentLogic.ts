/**
 * Asks the decision model which tab a picker search belongs to, for the `taxonomic-filter-search-intent`
 * experiment. Every arm asks, so control records what the other arms would have shown. Legacy surface only.
 */
export const taxonomicSearchIntentLogic = kea<taxonomicSearchIntentLogicType>([
    props({} as TaxonomicFilterLogicProps),
    key((props) => `${props.taxonomicFilterLogicKey}`),
    path((key) => ['lib', 'components', 'TaxonomicFilter', 'taxonomicSearchIntentLogic', key]),
    connect((props: TaxonomicFilterLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            projectLogic,
            ['currentProjectId'],
            taxonomicFilterLogic(props),
            ['activeTab', 'revealBarrierOpen', 'searchQuery', 'taxonomicGroupTypes', 'taxonomicGroups'],
        ],
        actions: [taxonomicFilterLogic(props), ['setActiveTab', 'setIntentPromotedGroupType', 'setSearchQuery']],
    })),
    actions({
        setIntent: (intent: SearchIntent | null) => ({ intent }),
        setVariant: (variant: SearchIntentVariant) => ({ variant }),
        acceptSuggestedSwitch: true,
    }),
    reducers({
        intent: [
            null as SearchIntent | null,
            {
                setIntent: (_, { intent }) => intent,
                setSearchQuery: () => null,
            },
        ],
        variant: [
            null as SearchIntentVariant | null,
            {
                setVariant: (_, { variant }) => variant,
            },
        ],
    }),
    selectors({
        suggestedSwitch: [
            (s) => [s.intent, s.variant, s.activeTab, s.searchQuery, s.taxonomicGroupTypes, s.taxonomicGroups],
            (
                intent: SearchIntent | null,
                variant: SearchIntentVariant | null,
                activeTab: TaxonomicFilterGroupType,
                searchQuery: string,
                taxonomicGroupTypes: TaxonomicFilterGroupType[],
                taxonomicGroups: TaxonomicFilterGroup[]
            ): SuggestedSwitch | null => {
                if (
                    variant !== 'banner' ||
                    !intent?.suggests_switch ||
                    !intent.group_type ||
                    intent.activeTab !== activeTab ||
                    intent.query !== searchQuery.trim()
                ) {
                    return null
                }
                const groupType = intent.group_type as TaxonomicFilterGroupType
                if (!taxonomicGroupTypes.includes(groupType)) {
                    return null
                }
                const groupName = taxonomicGroups.find((group) => group.type === groupType)?.name ?? groupType
                return { groupType, groupName }
            },
        ],
    }),
    listeners(({ actions, values }) => ({
        setSearchQuery: async ({ searchQuery }, breakpoint) => {
            const query = searchQuery.trim()
            if (searchIntentUnavailable || query.length < MIN_QUERY_LENGTH || query.length > MAX_QUERY_LENGTH) {
                return
            }
            await breakpoint(SEARCH_INTENT_DEBOUNCE_MS)

            // Read the flag only for a search the model can answer, so exposure means "could have seen a change".
            const variant = values.variant ?? values.featureFlags[FEATURE_FLAGS.TAXONOMIC_FILTER_SEARCH_INTENT]
            if (!isSearchIntentVariant(variant) || values.currentProjectId === null) {
                return
            }
            if (values.variant === null) {
                actions.setVariant(variant)
            }

            const activeTab = values.activeTab
            let response: SearchIntentResponseApi
            try {
                response = await mlInferenceSearchIntentClassifyCreate(String(values.currentProjectId), {
                    query,
                    active_group_type: activeTab,
                    available_group_types: values.taxonomicGroupTypes,
                    scene: sceneLogic.findMounted()?.values.activeSceneId ?? null,
                })
            } catch (error: any) {
                if (error?.status === 404) {
                    searchIntentUnavailable = true
                }
                return
            }
            breakpoint()
            actions.setIntent({ ...response, query, activeTab })
        },
        setIntent: ({ intent }) => {
            if (!intent || !values.variant) {
                return
            }
            const canPromote = intent.method === 'model' && intent.is_confident && !!intent.group_type
            // Promote only while the results still show skeletons, so no row moves under the cursor.
            const promoted = values.variant === 'promote' && canPromote && !values.revealBarrierOpen
            if (promoted) {
                actions.setIntentPromotedGroupType(intent.group_type as TaxonomicFilterGroupType)
            }
            // pinned: analytics event name and properties, the experiment reads them
            posthog.capture('taxonomic filter search intent predicted', {
                surface: legacyTaxonomicSurface(),
                variant: values.variant,
                activeTab: intent.activeTab,
                predictedGroupType: intent.group_type,
                confidence: intent.confidence,
                isConfident: intent.is_confident,
                source: intent.method,
                suggestsSwitch: intent.suggests_switch,
                wouldPromote: canPromote,
                shown: values.variant === 'banner' ? !!values.suggestedSwitch : promoted,
                // Value-shaped searches (emails, URLs) never reach the model, so a model answer carries no value.
                query: intent.method === 'model' ? intent.query : undefined,
            })
        },
        acceptSuggestedSwitch: () => {
            const suggestion = values.suggestedSwitch
            if (!suggestion) {
                return
            }
            // pinned: analytics event name, the experiment reads it
            posthog.capture('taxonomic filter search intent switched', {
                surface: legacyTaxonomicSurface(),
                fromGroupType: values.activeTab,
                toGroupType: suggestion.groupType,
            })
            actions.setActiveTab(suggestion.groupType)
        },
    })),
])
