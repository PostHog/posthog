export type SearchIntentVariant = 'control' | 'banner' | 'promote'

const SEARCH_INTENT_VARIANTS: SearchIntentVariant[] = ['control', 'banner', 'promote']

// Mirrors MIN_QUERY_CHARS and MAX_QUERY_CHARS in products/ml_inference/backend/logic/search_intent.py.
const MIN_QUERY_LENGTH = 2
const MAX_QUERY_LENGTH = 64
// Longer than a keystroke gap, so a person who types a word asks once and not once per letter.
const SEARCH_INTENT_DEBOUNCE_MS = 350

export interface SearchIntent extends SearchIntentResponseApi {
    query: string
    activeTab: TaxonomicFilterGroupType
}

export interface SuggestedSwitch {
    groupType: TaxonomicFilterGroupType
    groupName: string
}

// One 404 means the project is not enrolled in decisions, so the rest of the page load does not ask again.
let searchIntentUnavailable = false

export function resetSearchIntentAvailabilityForTests(): void {
    searchIntentUnavailable = false
}

export function isSearchIntentVariant(value: unknown): value is SearchIntentVariant {
    return SEARCH_INTENT_VARIANTS.includes(value as SearchIntentVariant)
}

