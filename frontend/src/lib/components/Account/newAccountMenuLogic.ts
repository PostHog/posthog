import { MakeLogicType, actions, connect, kea, path, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { organizationLogic } from 'scenes/organizationLogic'
import { teamLogic } from 'scenes/teamLogic'

import type { OrganizationType, TeamPublicType, TeamType } from '../../../types'

export interface ProjectListItem {
    type: 'project'
    id: number
    team: OrganizationType['teams'][number]
    isCurrent: boolean
    logoMediaId: string | null
}

export interface CreateProjectItem {
    type: 'create'
    id: 'create-new-project'
    label: string
}

/** A project on another PostHog instance, such as the organization's workspace in another cloud region. */
export interface ExternalProjectItem {
    type: 'external'
    id: string
    name: string
    url: string
}

export type ListItem = ProjectListItem | ExternalProjectItem | CreateProjectItem

/** Whether a name matches what the user typed in an account switcher's search field. */
export function matchesSwitcherSearch(name: string, search: string): boolean {
    return name.toLowerCase().includes(search.trim().toLowerCase())
}

export function openExternalProject(item: ExternalProjectItem): void {
    posthog.capture('project switcher external project opened')
    window.location.href = item.url
}

