import { MakeLogicType, getContext, kea, path } from 'kea'
import { urlToAction } from 'kea-router'

import { organizationLogic } from 'scenes/organizationLogic'
import { sceneLogic } from 'scenes/sceneLogic'

import { SidePanelTab } from '~/types'

import { SUPPORT_KIND_TO_SUBJECT, supportLogic } from './supportLogic'

// Mirrors navigationLogic's `mode === 'full'` (the condition that mounts <SidePanel />), derived from
// sources supportLogic can't import without a billingLogic init cycle. Keep here, not in supportLogic.
function shouldUseSidePanel(searchParams: Record<string, any>): boolean {
    const zenFromUrl = searchParams?.zen !== undefined && searchParams.zen !== 'false' && searchParams.zen !== '0'
    if (zenFromUrl) {
        return false
    }
    if (organizationLogic.findMounted()?.values.isCurrentOrganizationUnavailable) {
        return false
    }
    return sceneLogic.findMounted()?.values.sceneConfig?.layout !== 'plain'
}

// The scene chunk loads asynchronously, so `sceneId` (and the `sceneConfig` layout that shouldUseSidePanel
// reads) is null until it settles. Routing then reads `undefined !== 'plain'` as true and sends every
// plain-layout scene — login, signup, 2FA, verify email — to the side panel, which renders no support
// form. Wait for the scene to settle so the surface choice matches the page the user is on.
function whenSceneSettled(callback: () => void): void {
    const isSettled = (): boolean => {
        const scene = sceneLogic.findMounted()
        // No sceneLogic (e.g. the toolbar) means nothing to wait for. Otherwise the scene is settled
        // once its chunk has loaded (sceneId set) and no navigation is in flight (loadingScene cleared),
        // so the layout we read belongs to the page the user is actually on.
        return !scene || (scene.values.sceneId != null && scene.values.loadingScene == null)
    }
    if (isSettled()) {
        callback()
        return
    }
    const unsubscribe = getContext().store.subscribe(() => {
        if (isSettled()) {
            unsubscribe()
            callback()
        }
    })
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export type supportRouterLogicType = MakeLogicType<{}, {}>

export const supportRouterLogic = kea<supportRouterLogicType>([
    path(['lib', 'components', 'support', 'supportRouterLogic']),
    urlToAction(() => ({
        '*': (_, searchParams, hashParams) => {
            if (supportLogic.findMounted()?.values.isSupportFormOpen) {
                return
            }

            const [panel, ...panelOptions] = (hashParams['panel'] ?? '').split(':')
            const isSupportPanel = panel === SidePanelTab.Support
            const isLegacyModal = 'supportModal' in hashParams

            if (!isSupportPanel && !isLegacyModal) {
                return
            }

            whenSceneSettled(() => {
                // The form may have opened while we waited for the scene to settle.
                if (supportLogic.findMounted()?.values.isSupportFormOpen) {
                    return
                }

                const target = shouldUseSidePanel(searchParams) ? 'sidePanel' : 'modal'

                if (isSupportPanel) {
                    // `kind` is the only routable field left. Links written before the triage fields were
                    // removed carry `kind:area:severity:isEmailFormOpen`, so read the flag by value rather
                    // than by position — positionally, an old link's area would land in its slot.
                    const [kind] = panelOptions

                    if (kind === 'ticket') {
                        return
                    }

                    supportLogic.actions.openSupportForm({
                        kind: Object.keys(SUPPORT_KIND_TO_SUBJECT).includes(kind) ? kind : null,
                        isEmailFormOpen: panelOptions.includes('true') ? 'true' : 'false',
                        target,
                    })
                    return
                }

                // Legacy supportModal param
                const [kind] = (hashParams['supportModal'] || '').split(':')

                supportLogic.actions.openSupportForm({
                    kind: Object.keys(SUPPORT_KIND_TO_SUBJECT).includes(kind) ? kind : null,
                    target,
                })
            })
        },
    })),
])
