/**
 * Global setup logic - the single source of truth for task completion and UI state.
 *
 * This logic handles:
 * 1. Task completion/skipping (called from anywhere via findMounted())
 * 2. UI state for the global setup popover (selectedProduct, isGlobalModalOpen)
 *
 * External logics should call globalSetupLogic.findMounted()?.actions.markTaskAsCompleted(taskId)
 * to mark tasks as complete. This updates team.onboarding_tasks and tracks analytics.
 */
export const globalSetupLogic = kea<globalSetupLogicType>([
    path(['lib', 'components', 'ProductSetup', 'globalSetupLogic']),
    connect(() => ({
        values: [router, ['location'], sceneLogic, ['activeSceneProductKey']],
    })),
    actions({
        // Task actions - single source of truth for task state updates
        // All actions accept either a single task ID or an array of task IDs
        markTaskAsCompleted: (taskIdOrIds: SetupTaskId | SetupTaskId[], userInitiated: boolean = false) => ({
            taskIdOrIds,
            userInitiated,
        }),
        markTaskAsSkipped: (taskIdOrIds: SetupTaskId | SetupTaskId[]) => ({ taskIdOrIds }),
        unmarkTaskAsCompleted: (taskIdOrIds: SetupTaskId | SetupTaskId[]) => ({ taskIdOrIds }),
        unmarkTaskAsSkipped: (taskIdOrIds: SetupTaskId | SetupTaskId[]) => ({ taskIdOrIds }),

        // Internal actions for optimistic updates
        // null value means "this task should appear as unmarked"
        setOptimisticTaskStatuses: (statuses: Record<string, ActivationTaskStatus | null>) => ({ statuses }),
        clearOptimisticTaskStatuses: (taskIds: SetupTaskId[]) => ({ taskIds }),

        // UI actions for the global setup popover
        setSelectedProduct: (productKey: ProductKey) => ({ productKey }),
        openGlobalSetup: true,
        closeGlobalSetup: true,

        // Element highlighting after navigation
        setHighlight: (selector: string, pathname: string) => ({ selector, pathname }),
        clearHighlight: true,
    }),
    reducers({
        // Currently selected product in the global setup popover
        selectedProduct: [
            ProductKey.PRODUCT_ANALYTICS as ProductKey,
            {
                setSelectedProduct: (_, { productKey }) => productKey,
            },
        ],
        // Whether the global setup popover is open
        isGlobalModalOpen: [
            false,
            {
                openGlobalSetup: () => true,
                closeGlobalSetup: () => false,
            },
        ],
        // Element to highlight after navigation, bound to the route that asked for it. An unbound
        // highlight outlives its route and pulses whatever matches on a page opened later.
        highlight: [
            null as SetupHighlight | null,
            {
                setHighlight: (_, { selector, pathname }) => ({ selector, pathname }),
                clearHighlight: () => null,
            },
        ],
        // Optimistic task statuses - updated immediately before the API call completes, so the UI
        // responds instantly. An entry is dropped once the save lands or fails, which hands the task
        // back to the saved team state. null means "the user unmarked this task"; a null entry stays
        // for the session so an auto-completion cannot silently tick the task again.
        optimisticTaskStatuses: [
            {} as Record<string, ActivationTaskStatus | null>,
            {
                setOptimisticTaskStatuses: (state, { statuses }) => ({ ...state, ...statuses }),
                clearOptimisticTaskStatuses: (state, { taskIds }) => {
                    const newState = { ...state }
                    for (const taskId of taskIds) {
                        delete newState[taskId]
                    }
                    return newState
                },
            },
        ],
    }),
    selectors({
        availableProducts: [() => [], () => PRODUCTS_WITH_SETUP],
        // The product key from the current scene - filtered to only include products with setup
        // Used for auto-selecting the product in the popover
        sceneProductKey: [
            (s) => [s.activeSceneProductKey],
            (activeSceneProductKey: ProductKey | null): ProductKey | null => {
                if (activeSceneProductKey && PRODUCTS_WITH_SETUP.includes(activeSceneProductKey)) {
                    return activeSceneProductKey
                }
                return null
            },
        ],
        // Whether the current scene has a product key that doesn't have setup configured
        // Used to hide the Quick Start button on scenes for products without onboarding
        sceneHasNoSetup: [
            (s) => [s.activeSceneProductKey],
            (activeSceneProductKey: ProductKey | null): boolean => {
                return activeSceneProductKey !== null && !PRODUCTS_WITH_SETUP.includes(activeSceneProductKey)
            },
        ],
        // Whether the product selection is locked to the current scene
        isProductSelectionLocked: [
            (s) => [s.sceneProductKey],
            (sceneProductKey: ProductKey | null) => sceneProductKey !== null,
        ],
    }),
    // NOTE: Not using `connect` here because the teamLogic might not have mounted yet
    // by the time this logic is mounted
    listeners(({ actions, values }) => {
        // Every write to a task goes through one of these two, so the guard, the checklist and the
        // saved team state can never disagree about what a task's status is.
        const setTaskStatuses = (
            taskIds: SetupTaskId[],
            statuses: Record<string, ActivationTaskStatus | null>,
            eventName: string
        ): void => {
            actions.setOptimisticTaskStatuses(statuses)

            for (const taskId of taskIds) {
                posthog.capture(eventName, { task: taskId })
            }

            const teamLogic = globalTeamLogic.findMounted()
            if (!teamLogic) {
                return
            }
            const currentTeam = teamLogic.values.currentTeam
            if (!currentTeam || !('onboarding_tasks' in currentTeam)) {
                return
            }

            teamLogic.actions.updateCurrentTeam({
                onboarding_tasks: toSavedTaskStatuses(
                    mergeTaskStatuses(currentTeam.onboarding_tasks, values.optimisticTaskStatuses)
                ),
            })
        }

        const markTasks = (
            taskIdOrIds: SetupTaskId | SetupTaskId[],
            status: ActivationTaskStatus,
            eventName: string,
            userInitiated: boolean
        ): void => {
            const teamLogic = globalTeamLogic.findMounted()
            const currentTeam = teamLogic?.values.currentTeam
            if (!currentTeam || !('onboarding_tasks' in currentTeam)) {
                return
            }

            const taskIds = Array.isArray(taskIdOrIds) ? taskIdOrIds : [taskIdOrIds]
            const current = mergeTaskStatuses(currentTeam.onboarding_tasks, values.optimisticTaskStatuses)
            const statuses: Record<string, ActivationTaskStatus> = {}
            for (const taskId of taskIds) {
                if (current[taskId] === status) {
                    continue
                }
                // An auto-completion must not tick a task the user has just unmarked. Only the user
                // can put the checkmark back.
                if (!userInitiated && current[taskId] === null) {
                    continue
                }
                statuses[taskId] = status
            }
            const pendingTaskIds = Object.keys(statuses) as SetupTaskId[]
            if (pendingTaskIds.length === 0) {
                return
            }

            // Only re-open the popover if it was already open — avoids the popover popping
            // open uninvited on top of other surfaces (e.g. the welcome dialog) when team
            // settings get updated during onboarding and silently complete a task.
            if (status === ActivationTaskStatus.COMPLETED && values.isGlobalModalOpen) {
                actions.openGlobalSetup()
            }

            setTaskStatuses(pendingTaskIds, statuses, eventName)
        }

        // An unmark cannot be expressed in the saved team state, so it lives in the overlay as null
        // until the user marks the task again.
        const unmarkTasks = (taskIdOrIds: SetupTaskId | SetupTaskId[], eventName: string): void => {
            const taskIds = Array.isArray(taskIdOrIds) ? taskIdOrIds : [taskIdOrIds]
            const statuses: Record<string, null> = {}
            for (const taskId of taskIds) {
                statuses[taskId] = null
            }
            setTaskStatuses(taskIds, statuses, eventName)
        }

        return {
            markTaskAsCompleted: ({ taskIdOrIds, userInitiated }) => {
                markTasks(taskIdOrIds, ActivationTaskStatus.COMPLETED, 'product setup task completed', userInitiated)
            },

            markTaskAsSkipped: ({ taskIdOrIds }) => {
                // Only the popover skips a task, so a skip is always the user's own doing.
                markTasks(taskIdOrIds, ActivationTaskStatus.SKIPPED, 'product setup task skipped', true)
            },

            unmarkTaskAsCompleted: ({ taskIdOrIds }) => {
                unmarkTasks(taskIdOrIds, 'product setup task uncompleted')
            },

            unmarkTaskAsSkipped: ({ taskIdOrIds }) => {
                unmarkTasks(taskIdOrIds, 'product setup task unskipped')
            },

            // Once a save lands, the task belongs to the saved team state again - keeping the overlay
            // entry would freeze the checklist on a value the server has moved on from.
            [globalTeamLogic.actionTypes.updateCurrentTeamSuccess]: ({
                currentTeam,
            }: {
                currentTeam?: TeamPublicType | TeamType | null
            }) => {
                const savedTasks =
                    currentTeam && 'onboarding_tasks' in currentTeam ? (currentTeam.onboarding_tasks ?? {}) : {}
                const settledTaskIds = Object.entries(values.optimisticTaskStatuses)
                    // A null entry records an unmark, which the saved state cannot express, so it is
                    // kept for the session instead of settled here.
                    .filter(([taskId, status]) => status !== null && savedTasks[taskId] === status)
                    .map(([taskId]) => taskId as SetupTaskId)
                if (settledTaskIds.length > 0) {
                    actions.clearOptimisticTaskStatuses(settledTaskIds)
                }
            },

            // The save failed, so roll the checklist back to what is actually stored rather than
            // leaving the user with a checkmark that exists nowhere.
            [globalTeamLogic.actionTypes.updateCurrentTeamFailure]: () => {
                const taskIds = Object.keys(values.optimisticTaskStatuses) as SetupTaskId[]
                if (taskIds.length > 0) {
                    actions.clearOptimisticTaskStatuses(taskIds)
                }
            },
        }
    }),
    subscriptions(({ actions, values }) => ({
        // Drop a pending highlight as soon as the user leaves the route that asked for it
        location: ({ pathname }: { pathname: string }) => {
            if (values.highlight && values.highlight.pathname !== pathname) {
                actions.clearHighlight()
            }
        },
        // When the scene product key changes, auto-select it in the popover
        sceneProductKey: (sceneProductKey: ProductKey | null) => {
            if (sceneProductKey && sceneProductKey !== values.selectedProduct) {
                actions.setSelectedProduct(sceneProductKey)
            }
        },
    })),
])
