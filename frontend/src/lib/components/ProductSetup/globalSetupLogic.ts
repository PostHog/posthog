/**
 * The status every reader of the checklist must use: what the team has saved, with the pending
 * optimistic changes on top. A null value means the user unmarked the task and the save is either
 * in flight or already done.
 */
export function mergeTaskStatuses(
    savedTasks: Record<string, ActivationTaskStatus> | undefined,
    optimisticTaskStatuses: Record<string, ActivationTaskStatus | null>
): Record<string, ActivationTaskStatus | null> {
    return { ...savedTasks, ...optimisticTaskStatuses }
}

/** The same statuses in the shape the team stores: an unmarked task carries no entry at all. */
function toSavedTaskStatuses(
    statuses: Record<string, ActivationTaskStatus | null>
): Record<string, ActivationTaskStatus> {
    const savedTasks: Record<string, ActivationTaskStatus> = {}
    for (const [taskId, status] of Object.entries(statuses)) {
        if (status) {
            savedTasks[taskId] = status
        }
    }
    return savedTasks
}

