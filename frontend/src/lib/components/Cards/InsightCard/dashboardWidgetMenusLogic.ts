/** Copy / Move dashboard submenus for insight, text, and button widgets (placement + ACL). */
export const dashboardWidgetMenusLogic = kea<dashboardWidgetMenusLogicType>([
    path(['lib', 'components', 'Cards', 'InsightCard', 'dashboardWidgetMenusLogic']),
    props({} as DashboardWidgetMenusLogicProps),
    key((props) => `${props.instanceKey}-${props.dashboardId ?? 'nd'}`),
    actions({ loadDestinationDashboardsIfNeeded: true, loadMoreDestinationDashboards: true }),
    loaders({
        destinationPage: [
            null as PaginatedResponse<DashboardBasicType> | null,
            {
                loadDestinationDashboards: async (url?: string): Promise<PaginatedResponse<DashboardBasicType>> => {
                    const teamId = teamLogic.values.currentTeamId
                    if (teamId == null) {
                        return { next: null, previous: null, results: [] } as PaginatedResponse<DashboardBasicType>
                    }
                    const params = new URLSearchParams({ limit: '50', exclude_generated: 'true' })
                    return api.get(
                        url ?? `api/projects/${teamLogic.values.currentTeamIdStrict}/dashboards/?${params.toString()}`
                    )
                },
            },
        ],
    }),
    reducers({
        destinationDashboards: [
            [] as DashboardBasicType[],
            {
                loadDestinationDashboardsSuccess: (state, { destinationPage, payload }) =>
                    payload ? [...state, ...(destinationPage.results ?? [])] : (destinationPage.results ?? []),
            },
        ],
        hasMoreDestinationDashboards: [
            false,
            {
                loadDestinationDashboardsSuccess: (_, { destinationPage }) => destinationPage.next != null,
            },
        ],
    }),
    selectors(() => ({
        destinationDashboardsLoaded: [
            (s) => [s.destinationPage],
            (destinationPage: PaginatedResponse<DashboardBasicType> | null): boolean => destinationPage !== null,
        ],
        /** Dashboards where this widget (insight / text / button / …) is already placed. */
        dashboardIdsWithThisWidget: [
            (_, p) => [p.dashboards, p.dashboard_tiles, p.dashboardId],
            (
                dashboards: number[] | null | undefined,
                dashboard_tiles: DashboardTileBasicType[] | null | undefined,
                dashboardId: number | null | undefined
            ): Set<number> => {
                const set = new Set<number>()
                for (const rawId of dashboards ?? []) {
                    if (rawId != null) {
                        set.add(Number(rawId))
                    }
                }
                for (const t of dashboard_tiles ?? []) {
                    if (t.dashboard_id != null) {
                        set.add(Number(t.dashboard_id))
                    }
                }
                if (dashboardId != null) {
                    set.add(Number(dashboardId))
                }
                return set
            },
        ],
        /** Destinations for Copy to and Move to submenus (disabled rows explain why a target is unavailable). */
        copyToDestinations: [
            (s, p) => [s.destinationDashboards, s.dashboardIdsWithThisWidget, p.dashboardId],
            (
                destinationDashboards: DashboardBasicType[],
                dashboardIdsWithThisWidget: Set<number>,
                dashboardId: number | null | undefined
            ): DashboardWidgetPlacementDestination[] => {
                return destinationDashboards
                    .filter((d) => (dashboardId == null || d.id !== dashboardId) && canEditDestinationDashboard(d))
                    .map((d) => ({
                        dashboard: d,
                        disabledReason: dashboardIdsWithThisWidget.has(Number(d.id))
                            ? 'Already on this dashboard'
                            : undefined,
                    }))
            },
        ],
    })),
    listeners(({ actions, values }) => ({
        loadDestinationDashboardsIfNeeded: () => {
            if (!values.destinationDashboardsLoaded && !values.destinationPageLoading) {
                actions.loadDestinationDashboards()
            }
        },
        loadMoreDestinationDashboards: () => {
            if (values.hasMoreDestinationDashboards && !values.destinationPageLoading && values.destinationPage?.next) {
                actions.loadDestinationDashboards(values.destinationPage.next)
            }
        },
    })),
])
