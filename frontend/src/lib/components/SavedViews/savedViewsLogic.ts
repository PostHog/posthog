import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers } from 'kea'
import { loaders } from 'kea-loaders'

import { lemonToast } from '@posthog/lemon-ui'

import api from 'lib/api'
import { teamLogic } from 'scenes/teamLogic'

/** The fields every saved-view endpoint returns and the shared list renders. */
export interface SavedView {
    id: string
    short_id: string
    name: string
    filters?: Record<string, any>
    created_at: string
    created_by: { first_name?: string; email?: string } | null
}

/** Everything a product saves with a view apart from the name, for example `filters` and `columns`. */
export type SavedViewPayload = Record<string, unknown>

export interface SavedViewsLogicProps {
    /** Unique per product and viewer, because each viewer keeps its own list and dialog state. */
    key: string
    /** The project-scoped API path of the product's views endpoint, for example `logs/views`. */
    endpoint: string
}

const viewsUrl = (teamId: number | null, endpoint: string): string => `api/projects/${teamId}/${endpoint}`

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface savedViewsLogicValues {
    currentTeamId: number | null // teamLogic
    isModalOpen: boolean
    isSaveModalOpen: boolean
    viewName: string
    views: SavedView[]
    viewsLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface savedViewsLogicActions {
    closeModal: () => {
        value: true
    }
    closeSaveModal: () => {
        value: true
    }
    createView: (payload: SavedViewPayload & { name: string }) => SavedViewPayload & { name: string }
    createViewFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    createViewSuccess: (
        views: SavedView[],
        payload?: SavedViewPayload & { name: string }
    ) => {
        views: SavedView[]
        payload?: SavedViewPayload & { name: string }
    }
    deleteView: (shortId: string) => {
        shortId: string
    }
    loadView: (view: SavedView) => {
        view: SavedView
    }
    loadViews: () => any
    loadViewsFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadViewsSuccess: (
        views: SavedView[],
        payload?: any
    ) => {
        views: SavedView[]
        payload?: any
    }
    openModal: () => {
        value: true
    }
    openSaveModal: () => {
        value: true
    }
    saveView: (payload: SavedViewPayload) => {
        payload: SavedViewPayload
    }
    setViewName: (viewName: string) => {
        viewName: string
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface savedViewsLogicMeta {
    key: string
}

export type savedViewsLogicType = MakeLogicType<
    savedViewsLogicValues,
    savedViewsLogicActions,
    SavedViewsLogicProps,
    savedViewsLogicMeta
>

/**
 * List, create and delete state for a product's saved views. The product decides what a view
 * holds: it passes the payload to `saveView`, and listens to `loadView` to apply a view.
 */
export const savedViewsLogic = kea<savedViewsLogicType>([
    props({} as SavedViewsLogicProps),
    key((props) => props.key),
    path((key) => ['lib', 'components', 'SavedViews', 'savedViewsLogic', key]),

    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),

    actions({
        openModal: true,
        closeModal: true,
        openSaveModal: true,
        closeSaveModal: true,
        setViewName: (viewName: string) => ({ viewName }),
        saveView: (payload: SavedViewPayload) => ({ payload }),
        deleteView: (shortId: string) => ({ shortId }),
        loadView: (view: SavedView) => ({ view }),
    }),

    loaders(({ props, values }) => ({
        views: [
            [] as SavedView[],
            {
                loadViews: async () => {
                    // nosemgrep: prefer-codegen-api -- Shared across products, so the endpoint is a prop and no single generated function covers it.
                    const response = await api.get(`${viewsUrl(values.currentTeamId, props.endpoint)}/`)
                    return response.results
                },
                createView: async (payload: SavedViewPayload & { name: string }) => {
                    // nosemgrep: prefer-codegen-api -- Shared across products, so the endpoint is a prop and no single generated function covers it.
                    const created: SavedView = await api.create(
                        `${viewsUrl(values.currentTeamId, props.endpoint)}/`,
                        payload
                    )
                    lemonToast.success('View saved')
                    return [created, ...values.views]
                },
            },
        ],
    })),

    reducers({
        views: {
            deleteView: (state, { shortId }) => state.filter((v) => v.short_id !== shortId),
        },
        isModalOpen: [
            false,
            {
                openModal: () => true,
                closeModal: () => false,
                loadView: () => false,
            },
        ],
        isSaveModalOpen: [
            false,
            {
                openSaveModal: () => true,
                closeSaveModal: () => false,
                createViewSuccess: () => false,
            },
        ],
        viewName: [
            '',
            {
                setViewName: (_, { viewName }) => viewName,
                closeSaveModal: () => '',
                createViewSuccess: () => '',
            },
        ],
    }),

    listeners(({ actions, props, values }) => ({
        openModal: () => {
            actions.loadViews()
        },
        saveView: ({ payload }) => {
            const name = values.viewName.trim()
            if (!name) {
                return
            }
            actions.createView({ ...payload, name })
        },
        deleteView: async ({ shortId }) => {
            try {
                // nosemgrep: prefer-codegen-api -- Shared across products, so the endpoint is a prop and no single generated function covers it.
                await api.delete(`${viewsUrl(values.currentTeamId, props.endpoint)}/${shortId}/`)
                lemonToast.success('View deleted')
            } catch {
                lemonToast.error('Failed to delete view')
                actions.loadViews()
            }
        },
        createViewFailure: () => {
            lemonToast.error('Failed to save view')
        },
        loadViewsFailure: () => {
            lemonToast.error('Failed to load saved views')
        },
    })),
])
