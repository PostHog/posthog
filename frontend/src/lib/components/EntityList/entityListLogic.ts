export const DEFAULT_SERVER_PAGE_SIZE = 50

/** Search term, page and ordering. Everything a list can be narrowed by today. */
export interface EntityListFilters {
    search: string
    page: number
    orderBy: string | null
}

export interface EntityListLogicProps {
    definition: EntityListDefinition<any>
}

function defaultFilters(definition: EntityListDefinition<any>): EntityListFilters {
    return { search: '', page: 1, orderBy: definition.defaultOrderBy ?? null }
}

function cleanFilters(definition: EntityListDefinition<any>, values: Partial<EntityListFilters>): EntityListFilters {
    const defaults = defaultFilters(definition)
    return {
        search: String(values.search ?? defaults.search),
        page: Math.max(1, parseInt(String(values.page)) || defaults.page),
        orderBy: values.orderBy === undefined ? defaults.orderBy : values.orderBy,
    }
}

function pageSizeFor(definition: EntityListDefinition<any>): number {
    return definition.pageSize ?? DEFAULT_SERVER_PAGE_SIZE
}

