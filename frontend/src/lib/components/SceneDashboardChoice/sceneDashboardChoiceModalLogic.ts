import { MakeLogicType, actions, connect, kea, key, listeners, path, props, reducers, selectors } from 'kea'
import posthog from 'posthog-js'

import { createFuse } from 'lib/utils/fuseSearch'
import { Scene } from 'scenes/sceneTypes'
import { teamLogic } from 'scenes/teamLogic'
import { userLogic } from 'scenes/userLogic'

import { dashboardsModel } from '~/models/dashboardsModel'
import { DashboardBasicType } from '~/types'

import type { DashboardType, TeamPublicType, TeamType, UserType } from '../../../types'

export type DashboardCompatibleScenes =
    | Scene.ProjectHomepage
    | Scene.Person
    | Scene.Group
    | Scene.ProductAnalyticsHomeTab

export interface SceneDashboardChoiceModalProps {
    scene: DashboardCompatibleScenes
}

export type DashboardChoiceView = 'starter' | 'existing'

export const sceneDescription: Record<DashboardCompatibleScenes, string> = {
    [Scene.Person]: 'persons',
    [Scene.Group]: 'groups',
    [Scene.ProjectHomepage]: 'this project',
    [Scene.ProductAnalyticsHomeTab]: 'the product analytics Home tab',
}

// Scenes whose choice is team-scoped (currentTeam.<field>) rather than the per-user
// user.scene_personalisation default that other scenes use.
const TEAM_SCOPED_DASHBOARD_FIELD: Partial<Record<DashboardCompatibleScenes, keyof TeamType>> = {
    [Scene.ProjectHomepage]: 'primary_dashboard',
    [Scene.ProductAnalyticsHomeTab]: 'home_tab_dashboard',
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneDashboardChoiceModalLogicValues {
    nameSortedDashboards: (DashboardBasicType | DashboardType)[] // dashboardsModel
    currentTeam: TeamPublicType | TeamType | null // teamLogic
    user: UserType | null // userLogic
    currentDashboardId: number | null
    dashboardChoiceView: DashboardChoiceView
    dashboards: (DashboardBasicType | DashboardType)[]
    isOpen: boolean
    searchTerm: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface sceneDashboardChoiceModalLogicActions {
    loadDashboardsIfNeeded: () => {
        value: true
    } // dashboardsModel
    updateCurrentTeam: (payload: Partial<TeamType>) => Partial<TeamType> // teamLogic
    setUserScenePersonalisation: (
        scene: DashboardCompatibleScenes,
        dashboard: number
    ) => {
        dashboard: number
        scene: DashboardCompatibleScenes
    } // userLogic
    closeSceneDashboardChoiceModal: () => boolean
    setSceneDashboardChoice: (dashboardId: number | null) => {
        dashboardId: number | null
    }
    setSearchTerm: (searchTerm: string) => {
        searchTerm: string
    }
    showDashboardPicker: () => boolean
    showSceneDashboardChoiceModal: () => boolean
    showStarterOptions: () => boolean
}

