import { LogicWrapper, MakeLogicType, afterMount, kea, key, listeners, path, props } from 'kea'
import { loaders } from 'kea-loaders'

import { captureAccessControlEvent } from 'lib/utils/accessControlUtils'

import { accessControlsLogic } from '~/layout/navigation-3000/sidepanel/panels/access_control/ResourceAccessControlsV2/accessControlsLogic'

import {
    organizationsProjectsAccessControlManagementRetrieve,
    organizationsProjectsAccessControlManagementUpdate,
} from 'products/access_control/frontend/generated/api'
import type { AccessControlManagementApi } from 'products/access_control/frontend/generated/api.schemas'

export interface TerraformLockLogicProps {
    organizationId: string
    projectId: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface terraformLockLogicValues {
    lock: AccessControlManagementApi | null
    lockLoading: boolean
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface terraformLockLogicActions {
    loadLock: () => any
    loadLockFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadLockSuccess: (
        lock: AccessControlManagementApi,
        payload?: any
    ) => {
        lock: AccessControlManagementApi
        payload?: any
    }
    setLock: (managed: boolean) => boolean
    setLockFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    setLockSuccess: (
        lock: AccessControlManagementApi,
        payload?: boolean
    ) => {
        lock: AccessControlManagementApi
        payload?: boolean
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface terraformLockLogicMeta {
    key: number
}

export type terraformLockLogicType = MakeLogicType<
    terraformLockLogicValues,
    terraformLockLogicActions,
    TerraformLockLogicProps,
    terraformLockLogicMeta
>

export const terraformLockLogic: LogicWrapper<terraformLockLogicType> = kea<terraformLockLogicType>([
    props({} as TerraformLockLogicProps),
    key((props) => props.projectId),
    path((key) => ['lib', 'components', 'TerraformExporter', 'terraformLockLogic', key]),
    loaders(({ props }) => ({
        lock: [
            null as AccessControlManagementApi | null,
            {
                loadLock: async () =>
                    await organizationsProjectsAccessControlManagementRetrieve(props.organizationId, props.projectId),
                setLock: async (managed: boolean) =>
                    await organizationsProjectsAccessControlManagementUpdate(props.organizationId, props.projectId, {
                        managed,
                    }),
            },
        ],
    })),
    listeners(({ props }) => ({
        setLockSuccess: ({ lock }) => {
            // pinned: analytics event name, renaming breaks dashboards
            captureAccessControlEvent('access_control_terraform_lock_toggled', { managed: lock.managed })
            // The settings page disables its controls from can_edit, which the lock changes
            const settings = accessControlsLogic.findMounted({ projectId: String(props.projectId) })
            settings?.actions.loadDefaults()
            settings?.actions.loadRoles()
            settings?.actions.loadMembers()
        },
    })),
    afterMount(({ actions }) => {
        actions.loadLock()
    }),
])
