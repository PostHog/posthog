import { ApiError } from 'lib/api'
import { slackChannelId } from 'lib/integrations/slackChannel'
import { teamLogic } from 'scenes/teamLogic'

import { CommentType } from '~/types'

import { commentsSendToSlackCreate } from 'products/platform_features/frontend/generated/api'

export type SendCommentToSlackResult = { sent: boolean; detail: string | null }

/** Posts a comment to a Slack channel and records the outcome. `detail` is the backend's reason for a failure. */
export async function sendCommentToSlack(
    projectId: number | string,
    comment: Pick<CommentType, 'id' | 'scope'>,
    destination: { integrationId: number; channelId: string },
    source: 'composer' | 'menu'
): Promise<SendCommentToSlackResult> {
    let result: SendCommentToSlackResult = { sent: true, detail: null }
    try {
        // The comments API is project-scoped — currentTeamId diverges from the project id
        // for non-default environments and 404s.
        await commentsSendToSlackCreate(String(projectId), comment.id, {
            integration_id: destination.integrationId,
            channel_id: destination.channelId,
        })
    } catch (e) {
        // Surface the backend's actionable detail (bot not in channel, integration missing…)
        result = { sent: false, detail: e instanceof ApiError ? e.detail : null }
    }
    posthog.capture('comment sent to slack', { scope: comment.scope, source, success: result.sent })
    return result
}

