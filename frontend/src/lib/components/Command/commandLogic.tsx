import { MakeLogicType, actions, connect, kea, listeners, path, reducers, selectors } from 'kea'

import posthog from 'lib/posthog-typed'
import { teamLogic } from 'scenes/teamLogic'

/** Where the command menu open was initiated from, reported on the `command menu opened` event. */
export type CommandOpenSource =
    | 'keyboard-shortcut'
    | 'nav-search-button'
    | 'nav-search-bar'
    | 'nav-footer-hint'
    | 'nav-tools-row'
    | 'nav-panel-callout'

export const COMMAND_HISTORY_LIMIT = 5

export interface CommandHistoryItem {
    id: string
    name: string
    displayName?: string
    href?: string
    itemType?: string | null
    productCategory?: string | null
    groupNoun?: string | null
    tags?: string[]
    searchKeywords?: string[]
    disabledReason?: string
    teamId: number | null
}

export interface CommandHistoryItemCandidate {
    id: string
    name: string
    displayName?: string
    href?: string
    itemType?: string | null
    productCategory?: string | null
    groupNoun?: string | null
    tags?: string[]
    searchKeywords?: string[]
    disabledReason?: string
}

export const toCommandHistoryItem = (item: CommandHistoryItemCandidate, teamId: number | null): CommandHistoryItem => ({
    id: item.id,
    name: item.name,
    displayName: item.displayName,
    href: item.href,
    itemType: item.itemType,
    productCategory: item.productCategory,
    groupNoun: item.groupNoun,
    tags: item.tags,
    searchKeywords: item.searchKeywords,
    disabledReason: item.disabledReason,
    teamId,
})

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface commandLogicValues {
    currentTeamId: number | null // teamLogic
    commandHistory: CommandHistoryItem[]
    isCommandOpen: boolean
    recentlySelectedItems: CommandHistoryItem[]
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface commandLogicActions {
    closeCommand: () => {
        value: true
    }
    openCommand: (source: CommandOpenSource) => {
        source: CommandOpenSource
    }
    recordCommandSelection: (item: CommandHistoryItem) => {
        item: CommandHistoryItem
    }
    toggleCommand: (source: CommandOpenSource) => {
        source: CommandOpenSource
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface commandLogicMeta {
    __keaTypeGenInternalSelectorTypes: {
        recentlySelectedItems: (
            commandHistory: CommandHistoryItem[],
            currentTeamId: number | null
        ) => CommandHistoryItem[]
    }
}

export type commandLogicType = MakeLogicType<
    commandLogicValues,
    commandLogicActions,
    Record<string, any>,
    commandLogicMeta
>

export const commandLogic = kea<commandLogicType>([
    path(['lib', 'components', 'Command', 'commandLogic']),
    connect(() => ({
        values: [teamLogic, ['currentTeamId']],
    })),
    actions({
        openCommand: (source: CommandOpenSource) => ({ source }),
        closeCommand: true,
        recordCommandSelection: (item: CommandHistoryItem) => ({ item }),
        toggleCommand: (source: CommandOpenSource) => ({ source }),
    }),
    reducers({
        commandHistory: [
            [] as CommandHistoryItem[],
            { persist: true },
            {
                recordCommandSelection: (state, { item }) =>
                    [
                        item,
                        ...state.filter(
                            (historyItem) => historyItem.id !== item.id || historyItem.teamId !== item.teamId
                        ),
                    ].slice(0, COMMAND_HISTORY_LIMIT),
            },
        ],
        isCommandOpen: [
            false,
            {
                openCommand: () => true,
                closeCommand: () => false,
                toggleCommand: (state) => !state,
            },
        ],
    }),
    selectors({
        recentlySelectedItems: [
            (s) => [s.commandHistory, s.currentTeamId],
            (commandHistory: CommandHistoryItem[], currentTeamId: number | null): CommandHistoryItem[] =>
                commandHistory.filter((item) => item.teamId === currentTeamId),
        ],
    }),
    listeners(({ values }) => ({
        openCommand: ({ source }) => {
            posthog.capture('command menu opened', { source })
        },
        toggleCommand: ({ source }) => {
            if (values.isCommandOpen) {
                posthog.capture('command menu opened', { source })
            }
        },
    })),
])
