export type approvalsGateLogicType = MakeLogicType<
    approvalsGateLogicValues,
    approvalsGateLogicActions,
    Record<string, any>,
    approvalsGateLogicMeta
>

export const approvalsGateLogic = kea<approvalsGateLogicType>([
    path(['lib', 'approvals', 'approvalsGateLogic']),

    connect(() => ({
        values: [userLogic, ['hasAvailableFeature', 'user'], teamLogic, ['currentTeamIdStrict']],
    })),

    loaders(({ values }) => ({
        activePolicies: [
            [] as ApprovalPolicy[],
            {
                loadActivePolicies: async () => {
                    if (!values.hasAvailableFeature(AvailableFeature.APPROVALS)) {
                        return []
                    }

                    try {
                        // nosemgrep: prefer-codegen-api -- Legacy raw API call with a hand-written URL and an unchecked response type. Use approvalPoliciesList() from 'products/platform_features/frontend/generated/api' instead.
                        const response = await api.get(`api/projects/${values.currentTeamIdStrict}/approval_policies/`)
                        return (response.results || []).filter((p: ApprovalPolicy) => p.enabled)
                    } catch {
                        return []
                    }
                },
            },
        ],
    })),

    selectors({
        isApprovalsFeatureEnabled: [
            (s) => [s.hasAvailableFeature],
            (hasAvailableFeature: (feature: AvailableFeature, currentUsage?: number | undefined) => boolean): boolean =>
                hasAvailableFeature(AvailableFeature.APPROVALS),
        ],

        isApprovalRequired: [
            (s) => [s.isApprovalsFeatureEnabled, s.activePolicies],
            (isEnabled: boolean, policies: ApprovalPolicy[]) =>
                (actionKey: string): boolean => {
                    if (!isEnabled) {
                        return false
                    }
                    return policies.some((p: ApprovalPolicy) => p.action_key === actionKey && p.enabled)
                },
        ],

        // Freezing, unfreezing and resetting an experiment follow the "Update experiment" policy. The list
        // omits experiment policies before the organization scopes policies by flag owner, so this is false then.
        experimentOperationsNeedApproval: [
            (s) => [s.isApprovalsFeatureEnabled, s.activePolicies, s.user],
            (isEnabled: boolean, policies: ApprovalPolicy[], user: UserType | null): boolean => {
                if (!isEnabled) {
                    return false
                }
                const membershipLevel = user?.organization?.membership_level
                return policies.some(
                    (p: ApprovalPolicy) =>
                        p.enabled &&
                        p.action_key === ApprovalActionKey.EXPERIMENT_UPDATE &&
                        experimentUpdatePolicyCoversOperations(p.conditions) &&
                        !(
                            membershipLevel != null &&
                            p.bypass_org_membership_levels.map(Number).includes(membershipLevel)
                        )
                )
            },
        ],
    }),

    afterMount(({ actions }) => {
        actions.loadActivePolicies()
    }),
])
