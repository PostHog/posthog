const CONDITION_OPERATORS = ['>', '<', '>=', '<=', '==', '!=']

/** Mirrors the backend rule for when an "Update experiment" policy also holds freezing, unfreezing and resetting:
 * it reviews every change, including through a condition the backend cannot read, or any change to release conditions. */
export function experimentUpdatePolicyCoversOperations(conditions: unknown): boolean {
    if (!conditions || typeof conditions !== 'object' || Array.isArray(conditions)) {
        return true
    }
    const { type, field, operator, value } = conditions as Record<string, unknown>
    if (Object.keys(conditions).length === 0) {
        return true
    }
    if (type === 'before_after' || type === 'change_amount') {
        return !field || typeof operator !== 'string' || !CONDITION_OPERATORS.includes(operator) || value == null
    }
    if (type === 'any_change') {
        return !field || field === 'release_conditions'
    }
    return true
}

