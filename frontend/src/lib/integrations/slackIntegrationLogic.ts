export const slackIntegrationLogic = kea<slackIntegrationLogicType>([
    props({} as { id: number }),
    key((props) => props.id),
    path((key) => ['lib', 'integrations', 'slackIntegrationLogic', key]),
    connect(() => ({
        values: [preflightLogic, ['siteUrlMisconfigured', 'preflight']],
    })),
    actions({
        loadAllSlackChannels: (forceRefresh: boolean = false, search: string = '') => ({ forceRefresh, search }),
        loadAllSlackUsers: (forceRefresh: boolean = false, search: string = '') => ({ forceRefresh, search }),
        loadSlackUserById: (userId: string) => ({ userId }),
        loadSlackChannelById: (channelId: string) => ({ channelId }),
        setRecentlySubscribedChannelIds: (channelIds: string[]) => ({ channelIds }),
        setSlackIntegrationInactive: (message: string | null) => ({ message }),
    }),

    loaders(({ props, values, actions }) => ({
        allSlackChannels: [
            null as { channels: SlackChannelType[]; lastRefreshedAt: string; has_more?: boolean } | null,
            {
                loadAllSlackChannels: async ({ forceRefresh, search }, breakpoint) => {
                    if (search) {
                        await breakpoint(300)
                    }
                    try {
                        const response = await api.integrations.slackChannels(props.id, forceRefresh, { search })
                        if (forceRefresh) {
                            // Only a forced refresh provably reached Slack (a plain load can be
                            // served from the backend cache), so only it may hide the reconnect banner.
                            actions.setSlackIntegrationInactive(null)
                        }
                        return response
                    } catch (e: any) {
                        if (e?.code === SLACK_INTEGRATION_INACTIVE_ERROR_CODE) {
                            // Keep whatever we had and surface guidance inline instead of throwing,
                            // so kea-loaders doesn't fire its generic failure toast on every retry.
                            actions.setSlackIntegrationInactive(e.detail ?? SLACK_INTEGRATION_INACTIVE_FALLBACK_MESSAGE)
                            return values.allSlackChannels
                        }
                        throw e
                    }
                },
            },
        ],
        allSlackUsers: [
            null as SlackUsersResponseApi | null,
            {
                loadAllSlackUsers: async ({ forceRefresh, search }, breakpoint) => {
                    if (search) {
                        await breakpoint(300)
                    }
                    try {
                        const response = await integrationsUsersRetrieve(
                            String(ApiConfig.getCurrentProjectId()),
                            props.id,
                            {
                                ...(search ? { search } : {}),
                                ...(forceRefresh ? { force_refresh: true } : {}),
                            }
                        )
                        // A slower earlier search must not overwrite a newer one's results.
                        breakpoint()
                        if (forceRefresh) {
                            // Matches the channels loader: a cached-served search proves nothing
                            // about the token, so only a forced refresh clears the banner.
                            actions.setSlackIntegrationInactive(null)
                        }
                        return response
                    } catch (e: any) {
                        if (e?.code === SLACK_INTEGRATION_INACTIVE_ERROR_CODE) {
                            actions.setSlackIntegrationInactive(e.detail ?? SLACK_INTEGRATION_INACTIVE_FALLBACK_MESSAGE)
                            return values.allSlackUsers
                        }
                        throw e
                    }
                },
            },
        ],
        slackUserById: [
            null as SlackUserApi | null,
            {
                loadSlackUserById: async ({ userId }) => {
                    try {
                        const response = await integrationsUsersRetrieve(
                            String(ApiConfig.getCurrentProjectId()),
                            props.id,
                            { user_id: userId }
                        )
                        return response.users[0] ?? null
                    } catch (e: any) {
                        if (e?.code === SLACK_INTEGRATION_INACTIVE_ERROR_CODE) {
                            actions.setSlackIntegrationInactive(e.detail ?? SLACK_INTEGRATION_INACTIVE_FALLBACK_MESSAGE)
                            return values.slackUserById
                        }
                        throw e
                    }
                },
            },
        ],
        slackChannelById: [
            null as SlackChannelType | null,
            {
                loadSlackChannelById: async ({ channelId }, breakpoint) => {
                    await breakpoint(500)
                    try {
                        const res = await api.integrations.slackChannelsById(props.id, channelId)
                        // The by-id endpoint always calls Slack live, so a success is real proof
                        // the connection works again.
                        actions.setSlackIntegrationInactive(null)
                        return res.channels[0] || null
                    } catch (e: any) {
                        if (e?.code === SLACK_INTEGRATION_INACTIVE_ERROR_CODE) {
                            actions.setSlackIntegrationInactive(e.detail ?? SLACK_INTEGRATION_INACTIVE_FALLBACK_MESSAGE)
                            return values.slackChannelById
                        }
                        throw e
                    }
                },
            },
        ],
    })),

    reducers(({ props }) => ({
        _fetchedSlackChannels: [
            [] as SlackChannelType[],
            {
                // allSlackChannels is null when an inactive-integration load resolves with the
                // (empty) prior state instead of throwing — keep the existing channels in that case.
                loadAllSlackChannelsSuccess: (prev, { allSlackChannels }) => allSlackChannels?.channels ?? prev,
            },
        ],
        _fetchedSlackChannelById: [
            null as SlackChannelType | null,
            {
                loadSlackChannelByIdSuccess: (_, { slackChannelById }) => slackChannelById,
            },
        ],
        attemptedSlackUserIds: [
            {} as Record<string, true>,
            {
                loadSlackUserById: (state, { userId }) => ({ ...state, [userId]: true }),
                // A failed lookup keeps its marker: the picker's resolver effect fires whenever a
                // saved id is unmarked, so dropping it on failure would retry in an unbounded loop.
                // "Refresh members" is the explicit retry, and it clears the whole map.
                loadAllSlackUsers: (state, { forceRefresh }) => (forceRefresh ? {} : state),
            },
        ],
        _fetchedSlackUsersById: [
            {} as Record<string, SlackUserApi>,
            {
                loadSlackUserByIdSuccess: (state, { slackUserById, payload }) =>
                    slackUserById && payload ? { ...state, [payload.userId]: slackUserById } : state,
            },
        ],
        recentlySubscribedChannelIds: [
            getRecentSlackChannelIds(props.id),
            {
                setRecentlySubscribedChannelIds: (_, { channelIds }) => channelIds,
            },
        ],
        slackIntegrationInactiveMessage: [
            null as string | null,
            {
                // Only cleared by requests that provably reached Slack (forced refreshes, live
                // by-id lookups) — the loaders dispatch the clear themselves. A cache-served search
                // succeeding must not hide the banner while the token is still revoked.
                setSlackIntegrationInactive: (_, { message }) => message,
            },
        ],
    })),

    listeners(({ props, actions }) => ({
        loadAllSlackChannelsSuccess: () => {
            actions.setRecentlySubscribedChannelIds(getRecentSlackChannelIds(props.id))
        },
    })),

    selectors({
        slackChannels: [
            (s) => [s._fetchedSlackChannels, s._fetchedSlackChannelById],
            (
                _fetchedSlackChannels: SlackChannelType[],
                _fetchedSlackChannelById: SlackChannelType | null
            ): SlackChannelType[] => {
                const channels = [..._fetchedSlackChannels]
                if (_fetchedSlackChannelById && !channels.find((x) => x.id === _fetchedSlackChannelById.id)) {
                    channels.push(_fetchedSlackChannelById)
                }
                return channels
            },
        ],
        slackUsers: [
            (s) => [s.allSlackUsers, s._fetchedSlackUsersById],
            (
                allSlackUsers: SlackUsersResponseApi | null,
                _fetchedSlackUsersById: Record<string, SlackUserApi>
            ): SlackUserApi[] => {
                const listed = allSlackUsers?.users ?? []
                const listedIds = new Set(listed.map((user) => user.id))
                // Members resolved by direct lookup (saved recipients beyond the listed page, or
                // bare ids saved over the API) join the pool so their chips render a name.
                return [...listed, ...Object.values(_fetchedSlackUsersById).filter((user) => !listedIds.has(user.id))]
            },
        ],
        getUsersRefreshButtonDisabledReason: [
            (s) => [s.allSlackUsers],
            (allSlackUsers: SlackUsersResponseApi | null) => (): string => {
                const now = dayjs()
                if (allSlackUsers?.lastRefreshedAt) {
                    const earliestRefresh = dayjs(allSlackUsers.lastRefreshedAt).add(
                        SLACK_CHANNELS_MIN_REFRESH_INTERVAL_SECONDS,
                        'seconds'
                    )
                    if (now.isBefore(earliestRefresh)) {
                        const secondsLeft = Math.ceil(earliestRefresh.diff(now) / 1000)
                        return `You can refresh the members again in ${secondsLeft} second${
                            secondsLeft === 1 ? '' : 's'
                        }`
                    }
                }
                return ''
            },
        ],
        slackChannelsForPicker: [
            (s) => [s.slackChannels, s.recentlySubscribedChannelIds],
            (slackChannels: SlackChannelType[], recentlySubscribedChannelIds: string[]): SlackChannelType[] => {
                const recencyIndex = new Map(recentlySubscribedChannelIds.map((id, idx) => [id, idx]))
                return [...slackChannels].sort((a, b) => {
                    const aRecency = recencyIndex.get(a.id) ?? Number.POSITIVE_INFINITY
                    const bRecency = recencyIndex.get(b.id) ?? Number.POSITIVE_INFINITY
                    if (aRecency !== bRecency) {
                        return aRecency - bRecency
                    }
                    // Private channels the bot can't access come back from Slack without a name,
                    // so guard the comparator instead of assuming a string.
                    return (a.name ?? '').localeCompare(b.name ?? '')
                })
            },
        ],
        isMemberOfSlackChannel: [
            (s) => [s.slackChannels],
            (slackChannels: SlackChannelType[]) => {
                return (channel: string): boolean | null => {
                    const found = slackChannels.find((x) => x.id === slackChannelId(channel))
                    // Null when unknown so the picker's strict `=== false` membership gate doesn't fire spuriously.
                    return found ? (found.is_member ?? false) : null
                }
            },
        ],
        isPrivateChannelWithoutAccess: [
            (s) => [s.slackChannels],
            (slackChannels: SlackChannelType[]) => {
                return (channel: string) =>
                    slackChannels.find((x) => x.id === slackChannelId(channel))?.is_private_without_access ?? false
            },
        ],
        getChannelRefreshButtonDisabledReason: [
            (s) => [s.allSlackChannels],
            (allSlackChannels: { channels: SlackChannelType[]; lastRefreshedAt: string } | null) => (): string => {
                const now = dayjs()
                if (allSlackChannels) {
                    const earliestRefresh = dayjs(allSlackChannels.lastRefreshedAt).add(
                        SLACK_CHANNELS_MIN_REFRESH_INTERVAL_SECONDS,
                        'seconds'
                    )
                    if (now.isBefore(earliestRefresh)) {
                        const secondsLeft = Math.ceil(earliestRefresh.diff(now) / 1000)
                        return `You can refresh the channels again in ${secondsLeft} second${
                            secondsLeft === 1 ? '' : 's'
                        }`
                    }
                }
                return ''
            },
        ],
    }),
])
