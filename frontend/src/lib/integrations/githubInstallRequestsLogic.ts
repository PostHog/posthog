    dismissingRequestIds: string[]
    hasPendingInstallRequests: boolean
    installRequests: GitHubInstallRequestItemApi[]
    installRequestsResponse: GitHubInstallRequestListResponseApi | null
    installRequestsResponseLoading: boolean
