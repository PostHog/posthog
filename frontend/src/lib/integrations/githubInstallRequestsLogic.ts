import { MakeLogicType, actions, afterMount, connect, kea, listeners, path, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import { ApiError } from 'lib/api'
import { integrationsLogic } from 'lib/integrations/integrationsLogic'

import {
    usersIntegrationsGithubInstallRequestsDestroy,
    usersIntegrationsGithubInstallRequestsRetrieve,
} from '~/generated/core/api'
import type { GitHubInstallRequestItemApi, GitHubInstallRequestListResponseApi } from '~/generated/core/api.schemas'
import type { IntegrationType } from '~/types'

const INSTALL_REQUESTS_POLL_INTERVAL_MS = 15_000
// A background poll shouldn't keep hitting an endpoint that is down for the whole mount, so give up
// after a few consecutive failures rather than retrying (and reporting) every 15 seconds.
const MAX_CONSECUTIVE_POLL_FAILURES = 3

