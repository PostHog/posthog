/**
 * Durable "waiting for a GitHub org owner" state. GitHub only tells us the outcome through the
 * `installation.created` webhook, so while a request is pending and a consumer is mounted we poll
 * the list; once every request is resolved or dismissed the poll stops.
 */
export const githubInstallRequestsLogic = kea<githubInstallRequestsLogicType>([
    path(['lib', 'integrations', 'githubInstallRequestsLogic']),
    connect(() => ({
        values: [integrationsLogic, ['githubIntegrations', 'integrations']],
    })),
    actions({
        startPolling: true,
        stopPolling: true,
        dismissInstallRequest: (id: string) => ({ id }),
        dismissInstallRequestSuccess: (id: string) => ({ id }),
        dismissInstallRequestFailure: (id: string) => ({ id }),
    }),
    loaders({
        installRequestsResponse: [
            null as GitHubInstallRequestListResponseApi | null,
            {
                loadInstallRequests: async () => await usersIntegrationsGithubInstallRequestsRetrieve('@me'),
            },
        ],
    }),
    reducers({
        pollingSubscribers: [
            0,
            {
                startPolling: (state) => state + 1,
                stopPolling: (state) => Math.max(0, state - 1),
            },
        ],
        consecutiveLoadFailures: [
            0,
            {
                loadInstallRequestsSuccess: () => 0,
                loadInstallRequestsFailure: (state) => state + 1,
            },
        ],
        // Per-request in-flight state so each Dismiss button can disable itself while its DELETE
        // runs, rather than allowing a repeat click to fire a redundant delete + reload.
        dismissingRequestIds: [
            [] as string[],
            {
                dismissInstallRequest: (state, { id }) => (state.includes(id) ? state : [...state, id]),
                dismissInstallRequestSuccess: (state, { id }) => state.filter((x) => x !== id),
                dismissInstallRequestFailure: (state, { id }) => state.filter((x) => x !== id),
            },
        ],
    }),
    selectors({
        installRequests: [
            (s) => [s.installRequestsResponse],
            (response: GitHubInstallRequestListResponseApi | null): GitHubInstallRequestItemApi[] =>
                response?.results ?? [],
        ],
        installUrl: [
            (s) => [s.installRequestsResponse],
            (response: GitHubInstallRequestListResponseApi | null): string | null => response?.install_url ?? null,
        ],
        pendingInstallRequests: [
            (s) => [s.installRequests],
            (installRequests: GitHubInstallRequestItemApi[]): GitHubInstallRequestItemApi[] =>
                installRequests.filter((r) => r.status === 'pending'),
        ],
        // An approved request is durable server state that outlives the connection it unblocked, so
        // it drops out here once its installation is linked — otherwise the banner keeps offering
        // "Finish connecting" next to an already-connected surface, and the whole OAuth round trip
        // runs again. A request without an installation id (not expected once approved) stays
        // visible rather than being hidden on a missing match.
        approvedInstallRequests: [
            (s) => [s.installRequests, s.githubIntegrations, s.integrations],
            (
                installRequests: GitHubInstallRequestItemApi[],
                githubIntegrations: IntegrationType[],
                integrations: IntegrationType[] | null
            ): GitHubInstallRequestItemApi[] => {
                // An empty list while the integrations load reads as "nothing linked", which is the
                // same wrong prompt, so wait for the load before showing anything.
                if (integrations === null) {
                    return []
                }
                const linked = new Set(
                    githubIntegrations.map((integration) => String(integration.config?.installation_id))
                )
                return installRequests.filter(
                    (r) => r.status === 'approved' && (!r.installation_id || !linked.has(r.installation_id))
                )
            },
        ],
        hasPendingInstallRequests: [
            (s) => [s.pendingInstallRequests],
            (pendingInstallRequests: GitHubInstallRequestItemApi[]): boolean => pendingInstallRequests.length > 0,
        ],
    }),
    listeners(({ actions, values, cache }) => {
        const reconcilePolling = (): void => {
            // A response that never loaded also keeps the timer armed, so a failed first load retries
            // instead of hiding the banner for the rest of the mount.
            const shouldPoll =
                values.pollingSubscribers > 0 &&
                values.consecutiveLoadFailures < MAX_CONSECUTIVE_POLL_FAILURES &&
                (values.hasPendingInstallRequests || values.installRequestsResponse === null)
            if (shouldPoll && !cache.disposables.registry.has('poll')) {
                cache.disposables.add(() => {
                    const pollTimer = window.setInterval(
                        () => actions.loadInstallRequests(),
                        INSTALL_REQUESTS_POLL_INTERVAL_MS
                    )
                    return () => clearInterval(pollTimer)
                }, 'poll')
            } else if (!shouldPoll) {
                cache.disposables.dispose('poll')
            }
        }
        return {
            // `afterMount` is the only initial load — the banner is the only consumer that mounts this
            // logic, so a first subscriber always arrives at a logic that just ran it.
            startPolling: reconcilePolling,
            stopPolling: reconcilePolling,
            loadInstallRequestsSuccess: reconcilePolling,
            loadInstallRequestsFailure: reconcilePolling,
            dismissInstallRequest: async ({ id }) => {
                try {
                    await usersIntegrationsGithubInstallRequestsDestroy('@me', id)
                } catch (e) {
                    // A 404 means the row is already gone, so the dismiss effectively succeeded.
                    if (!(e instanceof ApiError && e.status === 404)) {
                        actions.dismissInstallRequestFailure(id)
                        throw e
                    }
                }
                actions.dismissInstallRequestSuccess(id)
                actions.loadInstallRequests()
            },
        }
    }),
    afterMount(({ actions }) => {
        actions.loadInstallRequests()
    }),
])
