import { MakeLogicType, actions, connect, kea, key, path, props, reducers, selectors } from 'kea'
import { loaders } from 'kea-loaders'

import api from 'lib/api'
import { dayjs } from 'lib/dayjs'
import { preflightLogic } from 'lib/logic/preflightLogic'

import { TwilioPhoneNumberType } from '~/types'

import type { PreflightStatus } from '../../types'

export const TWILIO_CHANNELS_MIN_REFRESH_INTERVAL_MINUTES = 5

// Match the backend `TwilioIntegrationInvalidCredentialsError` and `TwilioUnavailableError` default
// codes. A Twilio failure returns one of these instead of a 500, so the picker can show what to do
// next inline rather than a generic server error toast. An account that owns no numbers is not an
// error and keeps rendering the empty state.
export const TWILIO_PHONE_NUMBER_ERROR_CODES = ['twilio_integration_invalid_credentials', 'twilio_unavailable']
const TWILIO_PHONE_NUMBER_ERROR_FALLBACK_MESSAGE =
    'PostHog could not load phone numbers from Twilio. Try again in a few minutes.'

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface twilioIntegrationLogicValues {
    preflight: PreflightStatus | null // preflightLogic
    siteUrlMisconfigured: boolean // preflightLogic
    allTwilioPhoneNumbers: {
        lastRefreshedAt: string
        phone_numbers: TwilioPhoneNumberType[]
    } | null
    allTwilioPhoneNumbersLoading: boolean
    getPhoneNumberRefreshButtonDisabledReason: () => string
    twilioPhoneNumbers: TwilioPhoneNumberType[]
    twilioPhoneNumbersErrorMessage: string | null
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface twilioIntegrationLogicActions {
    loadAllTwilioPhoneNumbers: (forceRefresh?: boolean) => {
        forceRefresh: boolean
    }
    loadAllTwilioPhoneNumbersFailure: (
        error: string,
        errorObject?: any
    ) => {
        error: string
        errorObject?: any
    }
    loadAllTwilioPhoneNumbersSuccess: (
        allTwilioPhoneNumbers: {
            lastRefreshedAt: string
            phone_numbers: TwilioPhoneNumberType[]
        },
        payload?: {
            forceRefresh: boolean
        }
    ) => {
        allTwilioPhoneNumbers: {
            lastRefreshedAt: string
            phone_numbers: TwilioPhoneNumberType[]
        }
        payload?: {
            forceRefresh: boolean
        }
    }
    setTwilioPhoneNumbersError: (message: string | null) => {
        message: string | null
    }
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface twilioIntegrationLogicProps {
    id: number
}

// Generated by kea-typegen. Update if you're an agent, ignore if you're human.
export interface twilioIntegrationLogicMeta {
    key: number
    __keaTypeGenInternalSelectorTypes: {
        twilioPhoneNumbers: (
            allTwilioPhoneNumbers: {
                lastRefreshedAt: string
                phone_numbers: TwilioPhoneNumberType[]
            } | null
        ) => TwilioPhoneNumberType[]
        getPhoneNumberRefreshButtonDisabledReason: (
            allTwilioPhoneNumbers: {
                lastRefreshedAt: string
                phone_numbers: TwilioPhoneNumberType[]
            } | null
        ) => () => string
    }
}

export type twilioIntegrationLogicType = MakeLogicType<
    twilioIntegrationLogicValues,
    twilioIntegrationLogicActions,
    twilioIntegrationLogicProps,
    twilioIntegrationLogicMeta
>

export const twilioIntegrationLogic = kea<twilioIntegrationLogicType>([
    props({} as { id: number }),
    key((props) => props.id),
    path((key) => ['lib', 'integrations', 'twilioIntegrationLogic', key]),
    connect(() => ({
        values: [preflightLogic, ['siteUrlMisconfigured', 'preflight']],
    })),
    actions({
        loadAllTwilioPhoneNumbers: (forceRefresh: boolean = false) => ({ forceRefresh }),
        setTwilioPhoneNumbersError: (message: string | null) => ({ message }),
    }),

    loaders(({ props, values, actions }) => ({
        allTwilioPhoneNumbers: [
            null as { phone_numbers: TwilioPhoneNumberType[]; lastRefreshedAt: string } | null,
            {
                loadAllTwilioPhoneNumbers: async ({ forceRefresh }) => {
                    try {
                        const response = await api.integrations.twilioPhoneNumbers(props.id, forceRefresh)
                        actions.setTwilioPhoneNumbersError(null)
                        return response
                    } catch (e: any) {
                        if (TWILIO_PHONE_NUMBER_ERROR_CODES.includes(e?.code)) {
                            // Keep whatever we had and surface guidance inline instead of throwing,
                            // so kea-loaders does not fire its generic failure toast on every retry.
                            actions.setTwilioPhoneNumbersError(e.detail ?? TWILIO_PHONE_NUMBER_ERROR_FALLBACK_MESSAGE)
                            return values.allTwilioPhoneNumbers
                        }
                        throw e
                    }
                },
            },
        ],
    })),

    reducers({
        twilioPhoneNumbersErrorMessage: [
            null as string | null,
            {
                setTwilioPhoneNumbersError: (_, { message }) => message,
            },
        ],
    }),

    selectors({
        twilioPhoneNumbers: [
            (s) => [s.allTwilioPhoneNumbers],
            (allTwilioPhoneNumbers: { phone_numbers: TwilioPhoneNumberType[]; lastRefreshedAt: string } | null) => {
                return allTwilioPhoneNumbers?.phone_numbers ?? []
            },
        ],
        getPhoneNumberRefreshButtonDisabledReason: [
            (s) => [s.allTwilioPhoneNumbers],
            (allTwilioPhoneNumbers: { phone_numbers: TwilioPhoneNumberType[]; lastRefreshedAt: string } | null) =>
                (): string => {
                    const now = dayjs()
                    if (allTwilioPhoneNumbers) {
                        const earliestRefresh = dayjs(allTwilioPhoneNumbers.lastRefreshedAt).add(
                            TWILIO_CHANNELS_MIN_REFRESH_INTERVAL_MINUTES,
                            'minutes'
                        )
                        if (now.isBefore(earliestRefresh)) {
                            return `You can refresh the phone numbers again ${earliestRefresh.from(now)}`
                        }
                    }
                    return ''
                },
        ],
    }),
])
