from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

from hogli_commands.product import hoglint_status
from hogli_commands.product.hoglint_status import HoglintDebt, IsolatedLevel, IsolatedPasses
from hogli_commands.product.maturity import ProductScore, generate_detail

QUERY_OUTPUT = {
    "by": "package",
    "groups": [
        {"key": "(no package)", "counts": {"accepted": {"public-surface": 9}}},
        {
            "key": "harbor",
            "counts": {
                "accepted": {"public-surface": 3, "facade-signature": 2},
                "advisory": {"request-path": 4},
                "new": {"model-crossings": 1},
            },
        },
        {"key": "lantern", "counts": {"accepted": {"public-surface": 7}}},
    ],
}

LEDGER = (
    "# hoglint ledger, generated by `hoglint check --write-ledger`. Do not edit by hand.\n"
    "# schema=1 policy=0000\n"
    "level:isolated\tharbor\t1\n"
    "no-new-package-cycles\tlantern\tharbor\t1\n"
    "public-surface\tproducts.lantern.backend.models.Lamp\tproducts.harbor.backend.api\timport\t1\n"
)


def _write_turbo(product_dir: Path, tasks: dict) -> None:
    product_dir.mkdir(parents=True)
    (product_dir / "turbo.json").write_text(json.dumps({"extends": ["//"], "tasks": tasks}))
    scripts = dict.fromkeys(tasks, "echo")
    (product_dir / "package.json").write_text(
        json.dumps({"name": f"@posthog/products-{product_dir.name}", "scripts": scripts})
    )


def _fake_query(monkeypatch: pytest.MonkeyPatch, returncode: int, stdout: str, stderr: str) -> None:
    def run(args: list[str], **kwargs: object) -> subprocess.CompletedProcess[str]:
        return subprocess.CompletedProcess(args, returncode, stdout, stderr)

    monkeypatch.setattr(hoglint_status.subprocess, "run", run)


class TestIsolatedLevel:
    @pytest.mark.parametrize(
        "product, claims, write_ledger, expected",
        [
            ("harbor", True, True, "claims and passes"),
            ("lantern", True, True, "claims and fails"),
            ("harbor", False, True, "passes without claiming"),
            ("lantern", False, True, "neither claims nor passes"),
            ("harbor", True, False, "unknown: no hoglint.ledger"),
        ],
        ids=["claims_and_passes", "debt_line_is_no_pass", "passes_without_claim", "neither", "missing_ledger"],
    )
    def test_level_reads_only_level_lines(
        self, tmp_path: Path, product: str, claims: bool, write_ledger: bool, expected: str
    ) -> None:
        if write_ledger:
            (tmp_path / "hoglint.ledger").write_text(LEDGER)
        tasks = {"backend:contract-check": {"inputs": ["backend/facade/**"]}} if claims else {}
        product_dir = tmp_path / "products" / product
        _write_turbo(product_dir, tasks)

        level = IsolatedLevel.of(product, product_dir, IsolatedPasses.read(tmp_path))

        assert level.detail == expected


class TestHoglintDebt:
    def test_counts_belong_to_their_own_package(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        _fake_query(monkeypatch, 0, json.dumps(QUERY_OUTPUT), "")

        debt = HoglintDebt.load(tmp_path)

        assert debt.unavailable == ""
        assert debt.of("harbor").accepted == {"public-surface": 3, "facade-signature": 2}
        assert debt.of("harbor").new_total == 1
        assert debt.of("harbor").advisory == {"request-path": 4}
        assert debt.of("lantern").accepted_total == 7
        assert debt.of("beacon").accepted_total == 0

    @pytest.mark.parametrize(
        "returncode, stdout, stderr, expected",
        [
            (1, "", "Traceback...\nNo module named hoglint", "hoglint debt unavailable: No module named hoglint"),
            (
                2,
                "",
                "usage: hoglint\nhoglint: error: unrecognized arguments: --json",
                "hoglint debt unavailable: hoglint: error: unrecognized arguments: --json",
            ),
            (0, "groups: none", "", "hoglint debt unavailable: hoglint printed no valid JSON"),
            (
                0,
                json.dumps({"by": "package", "groups": [{"key": "harbor", "counts": {"accepted": {"x": "many"}}}]}),
                "",
                "hoglint debt unavailable: hoglint printed a group in an unknown shape",
            ),
        ],
        ids=["hoglint_missing", "hoglint_without_json_flag", "not_json", "wrong_shape"],
    )
    def test_detail_still_renders_when_debt_is_unavailable(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
        returncode: int,
        stdout: str,
        stderr: str,
        expected: str,
    ) -> None:
        _fake_query(monkeypatch, returncode, stdout, stderr)
        debt = HoglintDebt.load(tmp_path)
        score = ProductScore(product="harbor", debt=None, debt_unavailable=debt.unavailable)

        assert expected in generate_detail(score)
