def _read_call_argument(text: str, open_paren: int) -> str:
    """Return the argument text of the call whose ``(`` sits at ``open_paren``."""
    depth = 0
    for index in range(open_paren, len(text)):
        char = text[index]
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                return text[open_paren + 1 : index]
    return text[open_paren + 1 :]


def _split_top_level_args(text: str) -> list[str]:
    """Split a call's argument text on its top-level commas."""
    if not text.strip():
        return []
    args: list[str] = []
    depth = 0
    quote = ""
    start = 0
    for index, char in enumerate(text):
        if quote:
            quote = "" if char == quote else quote
            continue
        if char in "\"'`":
            quote = char
        elif char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "," and depth == 0:
            args.append(text[start:index])
            start = index + 1
    args.append(text[start:])
    return args


def _signature_params(signature: str) -> list[tuple[str, bool]]:
    """A method signature's parameters, in order, each with whether it is optional."""
    match = re.search(r"\((.*)\)\s*:\s*ApiRequest\s*\{", signature, re.S)
    if match is None:
        return []
    params = []
    for arg in _split_top_level_args(match.group(1)):
        name = arg.strip().split(":", 1)[0].strip()
        if not name:
            continue
        optional = name.endswith("?")
        params.append((name.rstrip("?").strip(), optional))
    return params


def _argument_segments(argument: str) -> tuple[str, ...]:
    """Path segments an argument contributes.

    A quoted string can pack several segments, and a template literal can mix them
    with interpolations: ``addPathComponent(`${issueId}/similar_issues`)`` is the
    detail route plus a literal action, not one opaque hole.
    """
    stripped = argument.strip()
    quoted = re.fullmatch(r"""(['"`])(.*)\1""", stripped, re.S)
    if quoted is None:
        return ("{}",)
    return tuple("{}" if "${" in part else part for part in quoted.group(2).split("/") if part)


