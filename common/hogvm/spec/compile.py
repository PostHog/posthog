# Run from project root (cd ../..)
# python3 -m common.hogvm.spec.compile
#
# Compiles common/hogvm/spec/stl.json — the cross-language HogVM STL contract — into the
# per-language artifacts each VM consumes, plus the generated arity conformance vectors.
# All outputs are committed; CI re-runs this script and fails on any diff, so the JSON spec
# is the only place the contract can change.

import re
import json
from typing import Any

from common.hogvm.python.operation import HOGQL_BYTECODE_IDENTIFIER, HOGQL_BYTECODE_VERSION, Operation

source = "common/hogvm/spec/stl.json"
target_ts = "common/hogvm/typescript/src/stl/stlSpec.ts"
target_rs = "rust/common/hogvm/src/stl_spec.rs"
target_vectors = "common/hogvm/spec/vectors/arity.json"

ALL_VMS = ["python", "typescript", "rust"]
# Dispatched through the async/blocking machinery rather than the plain native call path, so the
# generated CALL_GLOBAL probes would exercise the wrong dispatch site.
SKIP_VECTOR_FNS = {"sleep", "run"}

with open(source) as file:
    functions: dict[str, dict[str, Any]] = json.load(file)["functions"]


def implementations(entry: dict[str, Any]) -> list[str]:
    return entry.get("implementations", ALL_VMS)


# An invalid contract must not compile into plausible artifacts — a typo in a VM name would
# silently skip that function's vectors in every runner.
for name, entry in functions.items():
    impls = implementations(entry)
    if not impls or not set(impls) <= set(ALL_VMS):
        raise SystemExit(f"{name}: implementations must be a non-empty subset of {ALL_VMS}, got {impls}")
    min_args, max_args = entry["minArgs"], entry["maxArgs"]
    if not isinstance(min_args, int) or isinstance(min_args, bool) or min_args < 0:
        raise SystemExit(f"{name}: minArgs must be a non-negative integer, got {min_args!r}")
    if max_args is not None and (not isinstance(max_args, int) or isinstance(max_args, bool) or max_args < min_args):
        raise SystemExit(f"{name}: maxArgs must be null or an integer >= minArgs, got {max_args!r}")


with open(target_ts, "w") as output:
    output.write("// This file is generated by common/hogvm/spec/compile.py from common/hogvm/spec/stl.json\n")
    output.write("export interface StlSpecEntry {\n    minArgs: number\n    maxArgs: number | null\n}\n\n")
    output.write("export const STL_SPEC: Record<string, StlSpecEntry> = {\n")
    for name, entry in sorted(functions.items()):
        if "typescript" not in implementations(entry):
            continue
        max_args = "null" if entry["maxArgs"] is None else entry["maxArgs"]
        # oxfmt strips quotes from identifier keys, so emit them unquoted to stay format-stable
        key = name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name)
        output.write(f"    {key}: {{ minArgs: {entry['minArgs']}, maxArgs: {max_args} }},\n")
    output.write("}\n")

with open(target_rs, "w") as output:
    output.write("// This file is generated by common/hogvm/spec/compile.py from common/hogvm/spec/stl.json\n")
    output.write("// Do not edit by hand — change the JSON spec and re-run the compiler.\n\n")
    output.write("use std::collections::HashMap;\n\n")
    output.write("use once_cell::sync::Lazy;\n\n")
    output.write("use crate::error::VmError;\n\n")
    output.write("/// Declared (minArgs, maxArgs) for every builtin this VM implements, from the\n")
    output.write("/// cross-language STL contract. `None` means unbounded.\n")
    output.write("pub static STL_ARITY: Lazy<HashMap<&'static str, (usize, Option<usize>)>> = Lazy::new(|| {\n")
    output.write("    HashMap::from([\n")
    for name, entry in sorted(functions.items()):
        if "rust" not in implementations(entry):
            continue
        max_args = "None" if entry["maxArgs"] is None else f"Some({entry['maxArgs']})"
        output.write(f'        ("{name}", ({entry["minArgs"]}, {max_args})),\n')
    output.write("    ])\n")
    output.write("});\n\n")
    output.write("/// Reject a builtin call whose argument count is outside the contract arity, before the\n")
    output.write("/// function runs. A non-builtin name (an embedder ext fn) has no entry and passes through.\n")
    output.write("pub fn check_stl_arity(name: &str, arg_count: usize) -> Result<(), VmError> {\n")
    output.write("    let Some((min, max)) = STL_ARITY.get(name) else {\n")
    output.write("        return Ok(());\n")
    output.write("    };\n")
    output.write("    if arg_count < *min {\n")
    output.write("        return Err(VmError::TooFewArguments(name.to_string(), *min));\n")
    output.write("    }\n")
    output.write("    if let Some(max) = max {\n")
    output.write("        if arg_count > *max {\n")
    output.write("            return Err(VmError::TooManyArguments(name.to_string(), *max));\n")
    output.write("        }\n")
    output.write("    }\n")
    output.write("    Ok(())\n")
    output.write("}\n")

cases: list[dict[str, Any]] = []
for name, entry in sorted(functions.items()):
    if name in SKIP_VECTOR_FNS:
        continue
    impls = implementations(entry)
    min_args, max_args = entry["minArgs"], entry["maxArgs"]
    probes = []
    if min_args > 0:
        probes.append(("too-few", min_args - 1, f"Function {name} requires at least {min_args} arguments"))
    if max_args is not None:
        probes.append(("too-many", max_args + 1, f"Function {name} requires at most {max_args} arguments"))
    for label, arg_count, error in probes:
        bytecode: list[Any] = [HOGQL_BYTECODE_IDENTIFIER, HOGQL_BYTECODE_VERSION]
        for _ in range(arg_count):
            bytecode += [Operation.STRING, "1"]
        bytecode += [Operation.CALL_GLOBAL, name, arg_count]
        cases.append(
            {
                "name": f"{name}/{label}",
                "fn": name,
                "implementations": impls,
                "bytecode": bytecode,
                "expect": {"error": error},
            }
        )

with open(target_vectors, "w") as output:
    json.dump(
        {
            "$comment": "Generated by common/hogvm/spec/compile.py from stl.json. Every VM must "
            "produce the expected error for every case whose implementations include it.",
            "cases": cases,
        },
        output,
        indent=2,
    )
    output.write("\n")

print(f"Wrote {target_ts}, {target_rs}, and {len(cases)} arity vectors to {target_vectors}")  # noqa: T201
